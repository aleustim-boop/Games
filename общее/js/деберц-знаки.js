  'Мне везёт',          // про свои карты, а не про чужие
  'Не идёт карта',      // пожаловаться на себя — обидеть некого
  'Сейчас подумаю',     // объяснить свою задержку, пока другие ждут
  'Жду ваш ход',        // поторопить вежливо, без «ходи уже»
  'Спасибо за игру',    // чем партию заканчивают
  // Дописаны в конец, правило то же: можно сказать в лицо в любую минуту.
  'Ну и раздача!',      // про карты, а не про людей
  'Удачи!',             // пожелание — обидеть некого
  'Реванш?'             // позвать сыграть ещё
