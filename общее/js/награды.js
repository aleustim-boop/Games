/* =====================================================================
   Награды за приведённых друзей: что засчитал сервер и что дальше.

   Сервер считает друзей сам (server/привёл-друга.js): друг засчитывается,
   когда сыграет первую партию. Этот файл только спрашивает итог у двери
   POST /мои-награды и хранит последний ответ, чтобы экраны (профиль,
   позже — выбор рубашки) могли им пользоваться. Рисовать он ничего не
   рисует и колоду не трогает.

   Наружу одна дверь — window.Награды:

       Награды.обновить()        → обещание; спрашивает сервер, не срывается,
                                   отдаёт то же, что сколькоДрузей()
       Награды.сколькоДрузей()   → число друзей или null («не знаем»).
                                   null и 0 — разные вещи: ноль — сервер
                                   ответил «пока никого», null — ответа нет
                                   (не в Telegram, сервер молчит, ошибка)
       Награды.есть(ключ)        → true, если награда с таким ключом (например
                                   'рубашка-друг') у человека есть. Нет свежего
                                   ответа — смотрим в запомненный прошлый
       Награды.следующая()       → { друзей, осталось, награды, слова } —
                                   сколько друзей до следующей ступени и что
                                   она даст (слова — готовые слова сервера).
                                   null — «все награды получены» ИЛИ ответа нет;
                                   различать через сколькоДрузей() !== null
       Награды.наСобытие(дело)   → подписка: дело() вызывается каждый раз,
                                   когда пришёл свежий ответ сервера (только
                                   успешный). Возвращает функцию «отписаться»

   Событие — свой список подписчиков, а не CustomEvent окна: так работает
   и в проверках на node без браузера. Подписчику ответ не передаётся —
   он сам спрашивает сколькоДрузей()/следующая().

   Память: последний успешный ответ лежит в localStorage под ключом
   'rewards' (латиница, как велит договор про ключи). Только localStorage,
   без облака Telegram.

   Адрес сервера и подпись Telegram берём тем же приёмом, что
   общее/js/похвастаться.js: сперва window.Сеть.адрес(), иначе свой запасной
   порядок. Без подписи Telegram (игра открыта просто в браузере) сервер
   не спрашиваем вовсе — он всё равно не узнает человека.
   ===================================================================== */

'use strict';

(function () {

  const КЛЮЧ_ПАМЯТИ = 'rewards';

  /* Адрес сервера: те же имена ключей и правила, что в общее/js/похвастаться.js
     и общее/js/сеть.js. Разойдутся — сорвётся только этот необязательный блок. */
  const КЛЮЧ_АДРЕСА = 'server_address';
  const СТАРЫЙ_КЛЮЧ_АДРЕСА = 'подкидной-дурак:адрес-сервера';
  const АДРЕС_ПО_УМОЛЧАНИЮ = 'http://127.0.0.1:8790';
  const СВОЙ_КОМПЬЮТЕР =
    /^(localhost|127\.\d+\.\d+\.\d+|0\.0\.0\.0|\[[^\]]+\]|10\.\d+\.\d+\.\d+|192\.168\.\d+\.\d+|172\.(1[6-9]|2\d|3[01])\.\d+\.\d+)(:\d+)?$/i;
  const ВИТРИНА_БЕЗ_СЕРВЕРА = /(^|\.)github\.io(:\d+)?$/i;

  /* Сколько ждём сервер. Дольше — считаем, что он молчит: награды —
     украшение, ждать их с зависшим экраном нельзя. */
  const ЖДЁМ_ОТВЕТ = 4000;

  /* Последний успешный ответ в разобранном виде или null («не знаем»). */
  let последний = null;

  /* Номер последнего запроса: запоздавший старый ответ не должен
     затирать более свежий. */
  let номерЗапроса = 0;

  const подписчики = [];

  /* ---------- Страница и Telegram ---------- */

  function приложениеTelegram() {
    try {
      return (window.Telegram && window.Telegram.WebApp) || null;
    } catch (сбой) {
      return null;
    }
  }

  /** Подпись Telegram — по ней сервер узнаёт, кто просит. Нет — пусто. */
  function подписьTelegram() {
    const приложение = приложениеTelegram();
    return (приложение && приложение.initData) || '';
  }

  function изАдресаСтраницы(имена) {
    const место = window.location || {};
    for (const часть of [String(место.search || ''), String(место.hash || '')]) {
      try {
        const разбор = new URLSearchParams(часть.replace(/^[?#]/, ''));
        for (const имя of имена) {
          const значение = разбор.get(имя);
          if (значение) return значение;
        }
      } catch (сбой) {
        /* разбора адресов нет — считаем, что параметра нет */
      }
    }
    return '';
  }

  /** Адрес сервера; пусто — адреса нет (например, витрина на GitHub Pages). */
  function адресСервера() {
    if (window.Сеть && typeof window.Сеть.адрес === 'function') {
      try {
        const адрес = window.Сеть.адрес();
        if (адрес) return адрес;
      } catch (сбой) {
        /* спросим по-своему */
      }
    }
    const изСсылки = изАдресаСтраницы(['сервер', 'server']);
    if (изСсылки) return изСсылки.replace(/\/+$/, '');
    try {
      const вписан = (window.localStorage.getItem(КЛЮЧ_АДРЕСА) ||
                      window.localStorage.getItem(СТАРЫЙ_КЛЮЧ_АДРЕСА) || '').trim();
      if (вписан) return вписан.replace(/\/+$/, '');
    } catch (сбой) {
      /* память закрыта — идём на запасной */
    }
    try {
      if (window.location.protocol === 'file:') return АДРЕС_ПО_УМОЛЧАНИЮ;
      const хост = window.location.host || '';
      if (СВОЙ_КОМПЬЮТЕР.test(хост)) return АДРЕС_ПО_УМОЛЧАНИЮ;
      if (ВИТРИНА_БЕЗ_СЕРВЕРА.test(хост)) return '';
      return String(window.location.origin || '');
    } catch (сбой) {
      return '';
    }
  }

  /* ---------- Разбор ответа ---------- */

  /** Список наград ответа: только записи с текстовым ключом. */
  function разобратьНаграды(список) {
    return (Array.isArray(список) ? список : [])
      .filter(function (н) { return н && typeof н.ключ === 'string' && н.ключ; })
      .map(function (н) {
        return { ключ: н.ключ, слова: typeof н.слова === 'string' && н.слова ? н.слова : н.ключ };
      });
  }

  /**
   * Ответ сервера → то, что храним, или null, если ответ негодный.
   * «Негодный» — сервер не узнал человека (нет подписи или она неверна),
   * сказал «ок: false» или прислал число друзей не числом: такому ответу
   * нельзя верить, а «0 друзей» на его месте была бы ложью.
   */
  function разобратьОтвет(ответ) {
    if (!ответ || typeof ответ !== 'object') return null;
    if (ответ.ок !== true || ответ.узналиВас !== true) return null;
    if (!Number.isInteger(ответ.друзей) || ответ.друзей < 0) return null;
    const дальше = ответ.следующая;
    const следующая = (дальше && Number.isInteger(дальше.осталось) && дальше.осталось > 0)
      ? { друзей: Number(дальше.друзей) || 0, осталось: дальше.осталось, награды: разобратьНаграды(дальше.награды) }
      : null;
    return { друзей: ответ.друзей, награды: разобратьНаграды(ответ.награды), следующая: следующая };
  }

  /* ---------- Память ---------- */

  function запомнить(разобранный) {
    try {
      window.localStorage.setItem(КЛЮЧ_ПАМЯТИ, JSON.stringify(разобранный));
    } catch (сбой) {
      /* память закрыта (приватный режим) — живём без неё */
    }
  }

  /** Запомненный прошлый ответ или null. */
  function прочитатьПамять() {
    try {
      const сырое = window.localStorage.getItem(КЛЮЧ_ПАМЯТИ);
      if (!сырое) return null;
      const данные = JSON.parse(сырое);
      return данные && Array.isArray(данные.награды) ? данные : null;
    } catch (сбой) {
      return null;
    }
  }

  /* ---------- Запрос ---------- */

  /** Один запрос серверу. Обещание всегда выполняется: беда — null. */
  function спроситьСервер() {
    const подпись = подписьTelegram();
    const адрес = адресСервера();
    if (!подпись || !адрес || typeof fetch !== 'function') return Promise.resolve(null);

    const управление = typeof AbortController !== 'undefined' ? new AbortController() : null;
    let сторож = null;
    const таймаут = new Promise(function (готово) {
      сторож = setTimeout(function () {
        if (управление) управление.abort();
        готово(null);
      }, ЖДЁМ_ОТВЕТ);
    });
    const настройки = {
      method: 'POST',
      // Второй заголовок — пропуск через туннель, как у общее/js/сеть.js.
      headers: { 'Content-Type': 'application/json', 'bypass-tunnel-reminder': 'true' },
      body: JSON.stringify({ initData: подпись })
    };
    if (управление) настройки.signal = управление.signal;

    let запрос;
    try {
      запрос = fetch(адрес + '/мои-награды', настройки)
        .then(function (ответ) {
          if (!ответ || !ответ.ok) return null;
          return ответ.json().then(разобратьОтвет, function () { return null; });
        })
        .catch(function () { return null; });
    } catch (сбой) {
      clearTimeout(сторож);
      return Promise.resolve(null);
    }
    return Promise.race([запрос, таймаут]).then(function (итог) {
      clearTimeout(сторож);
      return итог;
    });
  }

  /* ---------- Двери наружу ---------- */

  function сказатьПодписчикам() {
    for (const дело of подписчики.slice()) {
      try {
        дело();
      } catch (сбой) {
        /* чужая ошибка подписчика не должна мешать остальным */
      }
    }
  }

  function сколькоДрузей() {
    return последний ? последний.друзей : null;
  }

  function есть(ключ) {
    const источник = последний || прочитатьПамять();
    if (!источник) return false;
    return источник.награды.some(function (н) { return н && н.ключ === ключ; });
  }

  function следующая() {
    if (!последний || !последний.следующая) return null;
    const дальше = последний.следующая;
    return {
      друзей: дальше.друзей,
      осталось: дальше.осталось,
      награды: дальше.награды.map(function (н) { return { ключ: н.ключ, слова: н.слова }; }),
      слова: дальше.награды.map(function (н) { return н.слова; })
    };
  }

  /** Спросить сервер. Никогда не срывается; отдаёт сколькоДрузей(). */
  function обновить() {
    номерЗапроса += 1;
    const моё = номерЗапроса;
    return спроситьСервер().then(function (разобранный) {
      // Пока ждали, ушёл более свежий запрос — его ответ главнее.
      if (моё !== номерЗапроса) return сколькоДрузей();
      последний = разобранный;
      if (разобранный) {
        запомнить(разобранный);
        сказатьПодписчикам();
      }
      return сколькоДрузей();
    });
  }

  function наСобытие(дело) {
    if (typeof дело !== 'function') return function () {};
    подписчики.push(дело);
    return function () {
      const место = подписчики.indexOf(дело);
      if (место !== -1) подписчики.splice(место, 1);
    };
  }

  window.Награды = {
    обновить: обновить,
    сколькоДрузей: сколькоДрузей,
    есть: есть,
    следующая: следующая,
    наСобытие: наСобытие
  };

})();
