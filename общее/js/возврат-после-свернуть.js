/* =====================================================================
   ВОЗВРАТ ПОСЛЕ «СВЕРНУТЬ»: свернул -> открыл -> оказался там же.

   У Telegram нет команды «свернуть мини-приложение», есть только «закрыть».
   Поэтому общее/js/telegram.js перед закрытием пишет в localStorage метку
   «куда вернуться» (ключ resume_at: { p: страница, d: открыт ли дурак,
   t: время }), а этот файл при следующем открытии:
     а) на витрине (index.html) читает метку, стирает её и переходит на
        страницу игры (или открывает лобби дурака);
     б) на странице игры один раз нажимает ту же кнопку «продолжить», что
        нажал бы сам игрок, — партия с ботом возвращается «без очков»,
        как и при ручном нажатии.
   Ни стилей, ни новых узлов этот файл не делает. Подключать после
   общее/js/telegram.js; на index.html — ещё и после общее/js/игры-реестр.js (список
   разрешённых страниц берётся из реестра).
   ===================================================================== */
(function () {
  'use strict';

  var КЛЮЧ_МЕТКИ = 'resume_at';          // пишет общее/js/telegram.js (латиницей — правило ключей памяти)
  var КЛЮЧ_ФЛАГА = 'resume_pending';     // в sessionStorage: «вернулись после Свернуть, нажми продолжить»
  var ВОЗРАСТ_МЕТКИ_МС = 12 * 60 * 60 * 1000;   // старее 12 часов — игрок пришёл не «продолжить»
  var ЖДАТЬ_КНОПКУ_МС = 8000;            // дольше не ждём: молча остаёмся в лобби
  var ШАГ_ОПРОСА_МС = 200;
  var СТРАНИЦА_ВИТРИНЫ = 'index.html';

  /* Кнопки «продолжить», по порядку важности. Первой — сетевая партия: она
     появляется после проверки у сервера и дороже партии с ботом. */
  var КНОПКИ_ПРОДОЛЖИТЬ = [
    'кнопка-вернуться-в-игру',   // общее/js/сеть.js: партия с друзьями ещё жива на сервере
    'кнопка-доиграть-с-ботом',   // дурак, шашки, нарды
    'кнопка-доиграть-шахматы',   // шахматы
    'деберц-продолжить',         // деберц
    'дом-продолжить',            // домино
    'море-продолжить',           // морской бой
    'кат-продолжить',            // катан
    'захват-продолжить',         // захват
    'continue'                   // судоку и игры на общее/casual/casual-ui.js
  ];

  /* Экраны index.html, на которых человек «внутри дурака» (не на витрине).
     Названия из index.html; класс видимости ставит game.js (показатьЭкран). */
  var ЭКРАНЫ_ДУРАКА = ['экран-лобби', 'экран-путь-правила', 'экран-путь-игроки', 'экран-путь-настройки',
    'экран-игры', 'экран-результата', 'экран-комнаты'];
  var КЛАСС_ВИДЕН = 'экран--виден';

  function имяСтраницы() {
    var имя = '';
    try {
      имя = String(window.location.pathname || '').split('/').pop();
      try { имя = decodeURIComponent(имя); } catch (ошибка) { /* оставляем как есть */ }
    } catch (ошибка) { return ''; }
    return имя === '' ? СТРАНИЦА_ВИТРИНЫ : имя;
  }

  function прочитатьПамять(хранилище, ключ) {
    try { return window[хранилище].getItem(ключ); } catch (ошибка) { return null; }
  }
  function записатьПамять(хранилище, ключ, значение) {
    try { window[хранилище].setItem(ключ, значение); } catch (ошибка) { /* память закрыта — не страшно */ }
  }
  function стеретьПамять(хранилище, ключ) {
    try { window[хранилище].removeItem(ключ); } catch (ошибка) { /* память закрыта — не страшно */ }
  }

  function разобратьМетку(текст) {
    if (!текст) return null;
    var метка;
    try { метка = JSON.parse(текст); } catch (ошибка) { return null; }
    if (!метка || typeof метка.p !== 'string' || метка.p === '') return null;
    if (typeof метка.t !== 'number' || !isFinite(метка.t)) return null;
    return { p: метка.p, d: метка.d === true, t: метка.t };
  }

  /* Приглашение сильнее метки: кто пришёл по ссылке-приглашению, должен попасть за стол. */
  function приглашениеВАдресе() {
    var хвосты = '';
    try { хвосты = String(window.location.search || '') + String(window.location.hash || ''); } catch (ошибка) { /* пусто */ }
    if (/(?:^|[?&#])(?:code|код|tgWebAppStartParam)=/.test(хвосты)) return true;
    try {
      var tg = window.Telegram && window.Telegram.WebApp;
      if (tg && tg.initDataUnsafe && tg.initDataUnsafe.start_param) return true;
    } catch (ошибка) { /* Telegram не отвечает — считаем, что приглашения нет */ }
    return false;
  }

  /* Человек сам выбрал игру ссылкой вида ?game=durak — метка ему не указ. */
  function выбранаИграВАдресе() {
    try { return /(?:^|[?&])game=/.test(String(window.location.search || '')); } catch (ошибка) { return false; }
  }

  function страницаРазрешена(страница) {
    var реестр = window.ИгрыРеестр;
    if (!реестр || typeof реестр.все !== 'function') return false;
    var игры = реестр.все();
    for (var i = 0; i < игры.length; i++) {
      if (!игры[i].спрятана && игры[i].страница === страница) return true;
    }
    return false;
  }

  // ------------------------------------------------------------ дорога «туда»

  function куда(метка) {
    if (метка.p === СТРАНИЦА_ВИТРИНЫ) return СТРАНИЦА_ВИТРИНЫ + '?game=durak';   // дорога из общее/js/вход-со-страниц.js
    return encodeURIComponent(метка.p);
  }

  function перейтиПоМетке(метка) {
    if (!страницаРазрешена(метка.p)) return;
    if (метка.p === СТРАНИЦА_ВИТРИНЫ && !метка.d) return;   // закрылись на витрине — она и так откроется
    записатьПамять('sessionStorage', КЛЮЧ_ФЛАГА, '1');
    window.location.replace(куда(метка));
  }

  function вернутьсяНаВитрине() {
    var сырое = прочитатьПамять('localStorage', КЛЮЧ_МЕТКИ);
    if (сырое === null) return;
    // Стираем ДО любого перехода: иначе «Все игры» снова кидало бы в игру (зацикливание)
    стеретьПамять('localStorage', КЛЮЧ_МЕТКИ);
    var метка = разобратьМетку(сырое);
    if (!метка) return;
    var возраст = Date.now() - метка.t;
    if (!(возраст >= 0 && возраст <= ВОЗРАСТ_МЕТКИ_МС)) return;
    if (приглашениеВАдресе() || выбранаИграВАдресе()) return;
    if (window.ИгрыРеестр) { перейтиПоМетке(метка); return; }
    // Реестр ещё не загружен — ждём конца разбора страницы, один раз
    if (typeof document !== 'undefined' && document.readyState === 'loading') {
      document.addEventListener('DOMContentLoaded', function () { перейтиПоМетке(метка); }, { once: true });
    }
  }

  // ------------------------------------------------------------ нажатие «продолжить»

  function видна(узел) {
    if (!узел || узел.hidden) return false;
    try {
      var стиль = window.getComputedStyle && window.getComputedStyle(узел);
      if (стиль && (стиль.display === 'none' || стиль.visibility === 'hidden')) return false;
    } catch (ошибка) { /* стиль не прочитался — судим по размерам */ }
    return узел.offsetWidth > 0 && узел.offsetHeight > 0;
  }

  function найтиВидимуюКнопку() {
    for (var i = 0; i < КНОПКИ_ПРОДОЛЖИТЬ.length; i++) {
      var узел = document.getElementById(КНОПКИ_ПРОДОЛЖИТЬ[i]);
      if (видна(узел)) return узел;
    }
    return null;
  }

  var СОБЫТИЯ_ИГРОКА = ['touchstart', 'pointerdown', 'mousedown', 'keydown', 'wheel'];

  function нажатьПродолжитьКогдаПоявится() {
    var прошло = 0;
    var таймер = null;
    function закончить() {
      if (таймер !== null) clearInterval(таймер);
      таймер = null;
      for (var i = 0; i < СОБЫТИЯ_ИГРОКА.length; i++) document.removeEventListener(СОБЫТИЯ_ИГРОКА[i], закончить, true);
    }
    function шаг() {
      var кнопка = найтиВидимуюКнопку();
      if (кнопка) {
        закончить();
        кнопка.click();   // один раз, ровно как нажал бы игрок
        return;
      }
      прошло += ШАГ_ОПРОСА_МС;
      if (прошло >= ЖДАТЬ_КНОПКУ_МС) закончить();   // не появилась — молча остаёмся в лобби
    }
    // Игрок коснулся экрана раньше нас — он рулит сам, автонажатие отменяем
    for (var i = 0; i < СОБЫТИЯ_ИГРОКА.length; i++) document.addEventListener(СОБЫТИЯ_ИГРОКА[i], закончить, true);
    таймер = setInterval(шаг, ШАГ_ОПРОСА_МС);
    шаг();
  }

  // ------------------------------------------------------------ перед закрытием

  function открытДурак() {
    if (имяСтраницы() !== СТРАНИЦА_ВИТРИНЫ) return false;
    for (var i = 0; i < ЭКРАНЫ_ДУРАКА.length; i++) {
      var экран = document.getElementById(ЭКРАНЫ_ДУРАКА[i]);
      if (экран && экран.classList && экран.classList.contains(КЛАСС_ВИДЕН)) return true;
    }
    return false;
  }

  /* Если приложение после «Свернуть» не закрылось (игрок снова трогает экран) —
     метка устарела: иначе «Все игры» потом кинуло бы обратно в игру. */
  function снятьМеткуЕслиЖивы() {
    function снять() {
      стеретьПамять('localStorage', КЛЮЧ_МЕТКИ);
      for (var i = 0; i < СОБЫТИЯ_ИГРОКА.length; i++) document.removeEventListener(СОБЫТИЯ_ИГРОКА[i], снять, true);
    }
    for (var i = 0; i < СОБЫТИЯ_ИГРОКА.length; i++) document.addEventListener(СОБЫТИЯ_ИГРОКА[i], снять, true);
  }

  function приПередЗакрытием() {
    var метка = разобратьМетку(прочитатьПамять('localStorage', КЛЮЧ_МЕТКИ));
    if (!метка) return;
    метка.d = открытДурак();
    записатьПамять('localStorage', КЛЮЧ_МЕТКИ, JSON.stringify(метка));
    снятьМеткуЕслиЖивы();
  }

  // ------------------------------------------------------------ запуск

  function запустить() {
    if (typeof window === 'undefined' || typeof document === 'undefined') return;
    // Сперва флаг от ПРОШЛОЙ загрузки: тот, что поставим ниже, этой странице не про нажатие
    var вернулись = прочитатьПамять('sessionStorage', КЛЮЧ_ФЛАГА) !== null;
    if (вернулись) {
      стеретьПамять('sessionStorage', КЛЮЧ_ФЛАГА);
      нажатьПродолжитьКогдаПоявится();
    }
    window.addEventListener('перед-закрытием', приПередЗакрытием);
    if (имяСтраницы() === СТРАНИЦА_ВИТРИНЫ) вернутьсяНаВитрине();
    // Устаревшая метка на странице игры не нужна: войти сюда можно было и напрямую
    else стеретьПамять('localStorage', КЛЮЧ_МЕТКИ);
  }

  запустить();
})();
