/* ---------------------------------------------------------------------
   Подделка «Image» для Части 2. Каждой картинке — свой src, лог всех
   запрошенных адресов, и через setTimeout(0) (как настоящая сеть)
   зовём onload для адресов из «успешные», иначе onerror.
   --------------------------------------------------------------------- */

function сделатьImage(лог, успешные) {
  return function Image() {
    const картинка = { onload: null, onerror: null };
    let собственныйАдрес = '';
    Object.defineProperty(картинка, 'src', {
      get: function () { return собственныйАдрес; },
      set: function (значение) {
        собственныйАдрес = значение;
        лог.push(значение);
        setTimeout(function () {
          if (успешные.has(значение)) { if (typeof картинка.onload === 'function') картинка.onload(); }
          else { if (typeof картинка.onerror === 'function') картинка.onerror(); }
        }, 0);
      }
    });
    return картинка;
  };
}

function рядИгрока(место, имя, очки, этоЯ, фото) {
  const строка = { место: место, имя: имя, очки: очки, побед: место, партий: место + 5, этоЯ: !!этоЯ };
  if (фото !== undefined) строка.фото = фото;
  return строка;
}

function fetchОтвет(данные) {
  return function () { return Promise.resolve({ json: function () { return Promise.resolve(данные); } }); };
}

/** Поднять экран с подделкой Image, вставленной ДО первого рендера.
    «фотоТелеграма» — необязательная строка: рейтинг-экран.js сам
    js/telegram.js не грузит, дверь «window.Телеграм.фотоИгрока» ему
    подставляем здесь же, напрямую, без сырого Telegram.WebApp. */
function поднятьСФото(настройки) {
  const поднятый = бр.поднять(исходник, { имяФайла: 'js/рейтинг-экран.js', fetch: настройки.fetch });
  поднятый.окно.Сеть = { адрес: function () { return 'https://тест.сервер'; } };
  поднятый.песочница.Image = сделатьImage(настройки.лог, настройки.успешные);
  if (настройки.фотоТелеграма) {
    поднятый.окно.Телеграм = { фотоИгрока: function () { return настройки.фотоТелеграма; } };
  }
  return поднятый;
}

