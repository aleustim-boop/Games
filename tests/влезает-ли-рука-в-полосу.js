/* =====================================================================
   ВЛЕЗАЕТ ЛИ РУКА В ОТВЕДЁННУЮ ЕЙ ПОЛОСУ — проверка прямо в браузере.

   ЗАЧЕМ ОНА НУЖНА. Владелец пожаловался: «когда карты в 2 ряда на руках,
   их плохо видно». Причина была в вёрстке: полоска руки держала высоту
   ровно в ОДНУ карту, и когда карт становилось много, два ряда делили эту
   высоту пополам — карта усыхала вдвое. А третий ряд и вовсе вылезал вниз,
   на кнопки «Беру» и «В меню»: карты были нарисованы поверх них.
   Так это выглядело до починки (280×636, 20 карт, три ряда):
       полоса руки  492..578,  а третий ряд карт  595..635 — под кнопками.

   ЧТО ПРОВЕРЯЕТ:
     1) ни одна карта руки не вылезает за полосу, которая ей отведена;
     2) ни одна карта не заезжает на строку кнопок («Беру», «Бито», «В меню»);
     3) ни одна карта не уходит за края окна;
     4) карта не мельче разумного: при двух рядах она обязана остаться
        такой же, как при одном (полоса растёт, а карта — нет);
     5) по каждой карте можно попасть пальцем — сверху не лежит ничего
        чужого (кроме соседних карт: они нарочно налезают друг на друга).

   Размер окна проверка НЕ меняет — это делает тот, кто гоняет браузер.
   Мерит она то окно, что сейчас, и говорит, какое видела.

   КАК ПОЛЬЗОВАТЬСЯ (партия уже идёт, карт в руке побольше):
       ПроверкаРуки.померить();     // разовый замер
       ПроверкаРуки.отчёт();        // что нашлось

   Чтобы набрать карт в руку, проще всего несколько раз нажать «Беру»:
       await ПроверкаРуки.набратьКарт(13);
   ===================================================================== */

(function () {
  'use strict';

  const беды = [];
  const сделано = [];

  function ждать(мс) { return new Promise(function (г) { setTimeout(г, мс); }); }
  function эл(id) { return document.getElementById(id); }

  function проверить(условие, что, подробности) {
    сделано.push(что);
    if (!условие) беды.push(подробности ? что + ' — ' + подробности : что);
  }

  function карты() {
    return [].slice.call(document.querySelectorAll('#карты-человека .карта'));
  }

  /** Сколько рядов вышло: считаем по разным «верхам» карт.
      Приподнятая карта отличается на две-три точки — такие верхи склеиваем. */
  function рядов(список) {
    const верхи = [];
    список.forEach(function (к) {
      const т = к.getBoundingClientRect().top;
      const рядом = верхи.some(function (в) { return Math.abs(в - т) <= 6; });
      if (!рядом) верхи.push(т);
    });
    return верхи.length;
  }

  function видна(узел) {
    if (!узел || узел.classList.contains('скрыт')) return false;
    const р = узел.getBoundingClientRect();
    return р.width > 0 && р.height > 0;
  }

  /**
   * Набрать карт в руку самым честным способом: жать «Беру» и «Бито».
   * Ничего внутри игры не трогаем — только кнопки, как живой человек.
   */
  async function набратьКарт(сколько) {
    const надо = сколько || 13;
    for (let шаг = 0; шаг < 400; шаг++) {
      if (карты().length >= надо) return 'в руке ' + карты().length + ' карт';
      const экран = эл('экран-игры');
      if (!экран || getComputedStyle(экран).display === 'none') return 'партия кончилась';
      if (видна(эл('кнопка-беру'))) { эл('кнопка-беру').click(); await ждать(420); continue; }
      if (видна(эл('кнопка-завершить'))) { эл('кнопка-завершить').click(); await ждать(420); continue; }
      if (видна(эл('кнопка-пас'))) { эл('кнопка-пас').click(); await ждать(420); continue; }
      /* Ход наш и кнопок нет — значит надо ходить картой, иначе партия
         просто встанет и рука никогда не наберётся. Кладём ту, которую
         игра сама подсветила как доступную (палец у неё «указующий»). */
      const доступная = карты().filter(function (к) {
        return getComputedStyle(к).cursor === 'pointer';
      })[0];
      if (доступная) { доступная.click(); await ждать(420); continue; }
      await ждать(280);
    }
    return 'в руке ' + карты().length + ' карт';
  }

  function померить() {
    беды.length = 0;
    сделано.length = 0;

    const полоса = эл('рука-человека');
    const панель = эл('панель-кнопок');
    const список = карты();
    if (!полоса) { беды.push('нет полосы руки на экране'); return отчёт(); }
    if (!список.length) { беды.push('в руке нет карт — мерить нечего'); return отчёт(); }

    const п = полоса.getBoundingClientRect();
    const кнопки = панель ? панель.getBoundingClientRect() : null;
    const рядовВсего = рядов(список);

    let ниже = 0;          // насколько сильнее всех карта вылезла вниз
    let наКнопках = 0;     // сколько карт залезло на строку кнопок
    let заОкном = 0;       // сколько карт вышло за края экрана
    let непопадаемых = 0;
    let самаяМелкая = Infinity;

    список.forEach(function (к) {
      const р = к.getBoundingClientRect();
      if (р.bottom > п.bottom + 1) ниже = Math.max(ниже, Math.round(р.bottom - п.bottom));
      if (кнопки && р.bottom > кнопки.top + 1 && р.top < кнопки.bottom) наКнопках++;
      if (р.bottom > window.innerHeight + 1 || р.top < -1 ||
          р.right > window.innerWidth + 1 || р.left < -1) заОкном++;
      if (р.height < самаяМелкая) самаяМелкая = Math.round(р.height);

      /* Попадание пальцем меряем по НИЖНЕЙ половине карты: сверху её
         нарочно накрывает соседка (карты лежат веером), а низ обязан
         быть свободен — именно туда и приходится палец. */
      const точка = document.elementFromPoint(
        р.left + р.width / 2, р.bottom - Math.max(3, р.height / 4));
      const своя = точка && (точка === к || к.contains(точка) ||
                             (точка.classList && точка.classList.contains('карта')));
      if (!своя) непопадаемых++;
    });

    проверить(ниже === 0, 'все карты руки внутри отведённой полосы',
      'самая нижняя вылезла на ' + ниже + ' точек (полоса кончается на ' +
      Math.round(п.bottom) + ')');
    проверить(наКнопках === 0, 'карты не заезжают на строку кнопок',
      наКнопках + ' карт лежит поверх кнопок «Беру»/«Бито»/«В меню»');
    проверить(заОкном === 0, 'ни одна карта не вышла за край экрана',
      заОкном + ' карт за краем');
    проверить(непопадаемых === 0, 'по каждой карте можно попасть пальцем',
      'до ' + непопадаемых + ' карт палец не достаёт: сверху лежит что-то чужое');

    /* Карта в два ряда не должна быть вдвое мельче, чем в один. Порог взят
       с запасом: на самом узком проверенном столе (280 точек) карта в один
       ряд выходит 40 точек высотой, и меньше 24 не бывает нигде. */
    проверить(самаяМелкая >= 24, 'карта не усохла до нечитаемого',
      'самая мелкая карта высотой ' + самаяМелкая + ' точек при ' +
      рядовВсего + ' рядах');

    return отчёт({
      карт: список.length,
      рядов: рядовВсего,
      высотаКарты: самаяМелкая,
      полосаРуки: Math.round(п.top) + '..' + Math.round(п.bottom),
      строкаКнопок: кнопки ? Math.round(кнопки.top) + '..' + Math.round(кнопки.bottom) : 'нет'
    });
  }

  function отчёт(мерки) {
    return {
      окно: window.innerWidth + '×' + window.innerHeight,
      мерки: мерки || null,
      проверок: сделано.length,
      бед: беды.length,
      беды: беды.slice(),
      итог: беды.length ? 'ЕСТЬ ЧТО ПОКАЗАТЬ ШТАБУ' : 'рука влезает и нажимается'
    };
  }

  window.ПроверкаРуки = { набратьКарт: набратьКарт, померить: померить, отчёт: отчёт };
  console.log('Проверка руки готова: await ПроверкаРуки.набратьКарт(13), потом ПроверкаРуки.померить()');
})();
