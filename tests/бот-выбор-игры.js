// Подмена https.request: и Telegram, и сервер комнат
// ---------------------------------------------------------------------------

const ОТПРАВЛЕНО = [];       // {метод, тело} — всё, что бот сказал Telegram
const К_СЕРВЕРУ = [];        // {путь, тело} — всё, что бот сказал серверу комнат
let очередьОбновлений = [];
let ждущийОпрос = null;      // функция: отдать пачку в последний «висящий» запрос getUpdates
let счётЗапросовGetUpdates = 0;
let номерСтола = 0;
let номерСообщения = 5000;

https.request = function (опции, колбэк) {
  const запрос = new EventEmitter();
  const хост = String((опции && (опции.hostname || опции.host)) || '');
  const путь = String((опции && опции.path) || '');
  let накоплено = null;

  function ответить(кодОтвета, тело, задержкаМс) {
    return setTimeout(function () {
      const ответ = new EventEmitter();
      ответ.setEncoding = function () {};
      ответ.statusCode = кодОтвета;
      колбэк(ответ);
      ответ.emit('data', JSON.stringify(тело));
      ответ.emit('end');
    }, задержкаМс || 0);
  }

  запрос.write = function (кусок) { накоплено = кусок; return true; };
  запрос.setTimeout = function () { return запрос; };
  запрос.end = function (телоBuf) {
    const сырое = телоBuf || накоплено;
    let тело = {};
    try { тело = сырое ? JSON.parse(сырое.toString('utf8')) : {}; } catch (ошибка) { /* не важно */ }

    if (хост === ХОСТ_КОМНАТ) {
      const читаемый = decodeURIComponent(путь);
      К_СЕРВЕРУ.push({ путь: читаемый, тело: сырое ? тело : undefined });
      if (читаемый === '/создать') {
        // Как ветка безХозяина в server/сервер.js: признаём только верный пропуск
        if (тело.безХозяина === true && тело.пропускБота === ПРОПУСК) {
          ответить(200, { код: 'ST' + String(++номерСтола).padStart(2, '0'), безХозяина: true, ждётСекунд: 300 });
        } else {
          ответить(200, { код: 'XX00', пропуск: 'чужой', состояние: {} });
        }
        return;
      }
      if (читаемый.indexOf('/стол?код=') === 0) {
        // За стол «сели» сразу — сторож отпускает его на первом же опросе
        ответить(200, { есть: true, игра: 'дурак', этап: 'ожидание', людей: 1, мест: 6, ждётЕщёСекунд: 300 });
        return;
      }
      ответить(404, { ошибка: 'Такого адреса на сервере нет' });
      return;
    }

    const метод = путь.slice(путь.lastIndexOf('/') + 1);
    ОТПРАВЛЕНО.push({ метод: метод, тело: тело });

    if (метод === 'getUpdates') {
      счётЗапросовGetUpdates++;
      if (очередьОбновлений.length) {
        const пачка = очередьОбновлений;
        очередьОбновлений = [];
        ответить(200, { ok: true, result: пачка }, 0);
      } else {
        /* Пустой ответ — через десять минут: отработавшие боты прежних
           сценариев не умирают, и быстрый пустой ответ позволил бы им
           перехватить апдейты следующего сценария. */
        const таймер = ответить(200, { ok: true, result: [] }, 10 * 60 * 1000);
        // Запомнили ждущий опрос: «следом» отдаёт вторую пачку именно в него
        ждущийОпрос = function (пачка) { clearTimeout(таймер); ответить(200, { ok: true, result: пачка }, 0); };
      }
      return;
    }
    if (метод === 'getMe') { ответить(200, { ok: true, result: { username: 'ТестБот' } }); return; }
    if (метод === 'sendMessage') { ответить(200, { ok: true, result: { message_id: ++номерСообщения } }); return; }
    ответить(200, { ok: true, result: true });
  };
  запрос.on = EventEmitter.prototype.on.bind(запрос);
  запрос.destroy = function () {};
  return запрос;
};

