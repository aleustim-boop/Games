/** Собираем стенд. «ломка» — функция «текст файла бота → испорченный текст»:
    её пробуем на каждом файле копии, своё место она обязана найти хотя бы в одном. */
function собратьСтенд(ломка) {
  const рут = fs.mkdtempSync(path.join(os.tmpdir(), 'бот-выбор-игры-'));
  временныеПапки.push(рут);
  const папкаБота = path.join(рут, 'bot');
  const папкаСервера = path.join(рут, 'server');
  fs.mkdirSync(папкаБота);
  fs.mkdirSync(папкаСервера);

  let испорчено = false;
  for (const имя of fs.readdirSync(path.join(КОРЕНЬ, 'bot'))) {
    if (!имя.endsWith('.js') || имя.indexOf('проверка-') === 0) continue;
    let текст = fs.readFileSync(path.join(КОРЕНЬ, 'bot', имя), 'utf8');
    if (ломка) {
      const испорченный = ломка(текст);
      if (испорченный !== текст) испорчено = true;
      текст = испорченный;
    }
    fs.writeFileSync(path.join(папкаБота, имя), текст, 'utf8');
  }
  if (ломка && !испорчено) {
    throw new Error('ломающий запуск: порча не нашла в файлах бота свою строку — ' +
      'проверку чинить раньше, чем верить её зелёному цвету');
  }

  fs.copyFileSync(ИСХОДНЫЕ_НАЗВАНИЯ, path.join(папкаСервера, 'названия.js'));
  fs.copyFileSync(path.join(path.dirname(ИСХОДНЫЕ_НАЗВАНИЯ), 'inline-столы.js'), path.join(папкаСервера, 'inline-столы.js'));
  require('./пути-проекта.js').создатьПапкиКода(path.join(папкаСервера, '..'));
  fs.copyFileSync(path.join(path.dirname(ИСХОДНЫЕ_НАЗВАНИЯ), '..', 'общее', 'js', 'языки.js'), path.join(папкаСервера, '..', 'общее', 'js', 'языки.js'));
  // Реестр игр нужен server/названия.js, чтобы знать, какие игры спрятаны
  fs.copyFileSync(path.join(path.dirname(ИСХОДНЫЕ_НАЗВАНИЯ), '..', 'общее', 'js', 'игры-реестр.js'), path.join(папкаСервера, '..', 'общее', 'js', 'игры-реестр.js'));
  fs.writeFileSync(path.join(папкаБота, '.env'),
    'BOT_TOKEN=' + выдуманныйТокен() + '\nGAME_URL=' + GAME_URL + '\n', 'utf8');

  return path.join(папкаБота, 'бот.js');
}

let номерАпдейта = 2000;

function сообщение(чат, типЧата, кто, текст) {
  return {
    update_id: ++номерАпдейта,
    message: {
      message_id: 1,
      chat: { id: чат, type: типЧата },
      from: { id: кто, first_name: 'Лена', last_name: 'Фамильева', is_bot: false },
      text: текст
    }
  };
}

/** Нажатие кнопки под сообщением бота с таким текстом. */
function нажатие(чат, типЧата, кто, данные, текстСообщения, номерСообщенияВЧате) {
  return {
    update_id: ++номерАпдейта,
    callback_query: {
      id: 'нажатие-' + номерАпдейта,
      from: { id: кто, first_name: 'Лена', is_bot: false },
      data: данные,
      message: {
        message_id: номерСообщенияВЧате,
        chat: { id: чат, type: типЧата },
        text: текстСообщения
      }
    }
  };
}

/** Запускаем свежего бота, отдаём пачку апдейтов и ждём, пока он разберёт
    её всю (второй запрос getUpdates) и сторожа столов доработают. */
async function прогнать(ломка, апдейты, следом) {
  const путьКБоту = собратьСтенд(ломка);
  очередьОбновлений = апдейты;
  const началоОтправок = ОТПРАВЛЕНО.length;
  const началоСервера = К_СЕРВЕРУ.length;
  const счётДоЗапроса = счётЗапросовGetUpdates;

  const настоящийЛог = console.log;
  console.log = function () {};
  try {
    /* Бот теперь запускается, только когда его открыли как программу
       (require.main === module). Подключаем стендового бота тем же путём,
       каким его открывает «node bot/бот.js»: как главный файл. Тогда он читает
       .env стенда и начинает опрос, а не молчит заглушкой. */
    require('module')._load(путьКБоту, null, true);
    for (let раз = 0; раз < 500 && счётЗапросовGetUpdates < счётДоЗапроса + 2; раз++) {
      await пауза(10);
    }
    /* Вторая пачка — отдельным опросом, когда первая уже разобрана: чаты в одной
       пачке бот разбирает одновременно, а порядок «сперва это, потом то» нужен
       только там, где один человек жмёт кнопки подряд. */
    if (следом && счётЗапросовGetUpdates >= счётДоЗапроса + 2) {
      ждущийОпрос(следом);
      for (let раз = 0; раз < 500 && счётЗапросовGetUpdates < счётДоЗапроса + 3; раз++) {
        await пауза(10);
      }
    }
    /* Оформление бота (подсказки команд) идёт фоном, уже после начала опроса:
       даём ему дойти до обоих списков (в группах и в личке), не дольше пяти секунд. */
    for (let раз = 0; раз < 500; раз++) {
      const вГруппах = ОТПРАВЛЕНО.slice(началоОтправок).some(function (з) {
        return з.метод === 'setMyCommands' && !з.тело.language_code && з.тело.scope && з.тело.scope.type === 'all_group_chats';
      });
      const вЛичке = ОТПРАВЛЕНО.slice(началоОтправок).some(function (з) {
        return з.метод === 'setMyCommands' && !з.тело.language_code && з.тело.scope && з.тело.scope.type === 'all_private_chats';
      });
      if (вГруппах && вЛичке) break;
      await пауза(10);
    }
  } finally {
    console.log = настоящийЛог;
  }
  if (счётЗапросовGetUpdates < счётДоЗапроса + 2) {
    throw new Error('бот на стенде не дошёл до второго запроса новостей — стенд не работает');
  }
  return { сказано: ОТПРАВЛЕНО.slice(началоОтправок), серверу: К_СЕРВЕРУ.slice(началоСервера) };
}

function вЧат(сказано, метод, чат) {
  return сказано.filter(function (з) { return з.метод === метод && з.тело.chat_id === чат; });
}
function создания(прогон, чат) {
  return прогон.серверу.filter(function (з) {
    return з.путь === '/создать' && (чат === undefined || (з.тело && з.тело.чат === чат));
  });
}
function кнопки(ответ) {
  const ряды = (ответ && ответ.тело.reply_markup && ответ.тело.reply_markup.inline_keyboard) || [];
  return [].concat.apply([], ряды);
}
/** Метка игры в ссылке «Сесть за стол»: «shahmaty_ST01-…» → «shahmaty»; у дурака — ''. */
function меткаВСсылке(ответ) {
  const кнопка = кнопки(ответ)[0];
  if (!кнопка || !кнопка.url) return null;
  const хвост = new URL(кнопка.url).searchParams.get('startapp') || '';
  const сМеткой = /^([a-z]+)_/.exec(хвост);
  return сМеткой ? сМеткой[1] : '';
}

