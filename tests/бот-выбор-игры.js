/* =====================================================================
   ПРОВЕРКА: бот спрашивает, во что играем, и открывает стол любой игры
   (этап Э2 плана штаб/план-бот-группы.md).

   Что проверяем:
     1. «/play» и «/играть» без слова (в группе и в личке) — вопрос
        «Во что играем?» и кнопки всех игр из server/названия.js, у каждой
        callback_data «stol:<метка>» не длиннее 64 байт; стол при этом
        ещё не создаётся;
     2. нажатие кнопки — ответ на нажатие (answerCallbackQuery), просьба
        серверу о столе БЕЗ ХОЗЯИНА этой игры с пропуском бота и номером
        чата, а меню превращается в приглашение (editMessageText) со
        ссылкой, в которой метка игры;
     3. кнопка под чужим текстом («Реванш?» под итогом партии) — тот текст
        не трогаем, приглашение идёт новым сообщением;
     4. незнакомая метка в кнопке — только ответ на нажатие, стола нет;
        двое нажали одно меню — второе приглашение идёт отдельным
        сообщением; отказ по кнопке — всплывающим окном, не в чат;
     5. команды игр: «/monopoly», «/шахматы», «/морской_бой», «/durak»,
        «/дурак» — стол сразу, без вопроса; «/играть в нарды»,
        «/play shashki» — тоже; «/играть преферанс» — вопрос;
     6. в группе команда игры с чужим именем («/monopoly@ДругойБот») —
        тишина, со своим — стол;
     7. подсказки команд: play и метки всех игр — и для личек, и для групп.

   Как: копия bot/*.js и server/названия.js во временной папке с поддельным
   .env; https.request подменён на весь процесс и играет сразу две роли —
   Telegram (api.telegram.org) и сервер комнат (адрес из «?сервер=»).
   Настоящий .env не читается, в сеть ничего не уходит.

   Ломающие запуски — в конце: копию бота (бот.js или стол-из-чата.js)
   портим по очереди, и на каждой порче проверка обязана покраснеть.

   Запуск:  node tests/бот-выбор-игры.js
   ===================================================================== */

'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const https = require('https');
const crypto = require('crypto');
const { EventEmitter } = require('events');

const КОРЕНЬ = path.join(__dirname, '..');
const ИСХОДНЫЕ_НАЗВАНИЯ = path.join(КОРЕНЬ, 'server', 'названия.js');
const Названия = require(ИСХОДНЫЕ_НАЗВАНИЯ);

const временныеПапки = [];

/* Каждый бот на стенде вешает свой обработчик Ctrl+C, а ботов здесь
   десятки — без этой строки Node ругается на «утечку» обработчиков. */
process.setMaxListeners(0);

function пауза(мс) { return new Promise(function (готово) { setTimeout(готово, мс); }); }

/* Выдуманный токен собран из кусочков — GitHub узнаёт токены Telegram
   по виду строки и присылает ложную тревогу об утечке, если написать
   его одной строкой (см. объяснение в tests/проверка-бота-лаунчера.js). */
function выдуманныйТокен() {
  const номерБота = [1, 2, 3, 4, 5, 6, 7, 8, 9, 0].join('');
  return номерБота + ':' + 'тест'.repeat(9);
}

/* Пропуск бота считаем так же, как он сам и как сервер: sha256 от токена. */
const ПРОПУСК = crypto.createHash('sha256')
  .update('стол-из-чата:' + выдуманныйТокен(), 'utf8').digest('hex');

const ХОСТ_КОМНАТ = 'komnaty.primer';
const АДРЕС_КОМНАТ = 'https://' + ХОСТ_КОМНАТ;
const GAME_URL = 'https://igra.primer/sbornik?сервер=' + АДРЕС_КОМНАТ;

const ВОПРОС = 'Во что играем?';

