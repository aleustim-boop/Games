'use strict';

/* =====================================================================
   МОРСКОЙ БОЙ: СВОЯ «море-шапка» ЗАМЕНЕНА ОБЩЕЙ ВЕРХНЕЙ СТРОКОЙ «‹ ⋯»
   (node, по разметке — браузер не нужен).

   Что смотрим в морской-бой.html, на экране партии (#экран-игры):
     1. класса «море-шапка» нет нигде — ни в разметке, ни в css игры;
     2. есть общая строка .верх-игры с двумя кнопками:
        data-назад и data-меню (aria-controls="лист-игры");
     3. полезное из прежней шапки не потеряно: заголовок «Морской бой»,
        кнопки «Правила» (#море-правила) и «Сдаться» (#море-сдаться)
        остались под строкой, в .море-заголовок;
     4. лист «⋯» (#лист-игры) есть, а js/морской-бой-экран.js вешает
        на data-назад и data-меню обработчики и подключает ЛистЕщё
        для экрана партии.
   Ноль найденного — провал, не пропуск.

   Ломающий прогон (--сломать): порченые КОПИИ морской-бой.html и css
   во временной папке; файлы проекта не трогаем. Каждая порча обязана
   дать красное.

   Запуск:
       node tests/ночь-море-шапка.js
       node tests/ночь-море-шапка.js --сломать
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const ПРОЕКТ = path.join(__dirname, '..');
const ФАЙЛЫ = { html: 'морской-бой.html', css: 'style-морской-бой.css', js: path.join('js', 'морской-бой-экран.js') };

let всего = 0;
let провалов = 0;
function проверить(условие, слова) {
  всего++;
  if (условие) console.log('  ок    — ' + слова);
  else { провалов++; console.log('  ПЛОХО — ' + слова); }
}

function довод(имя) { const г = process.argv.indexOf(имя); return г !== -1 ? process.argv[г + 1] : null; }

/** Текст файла: из подмены (копия для порчи) или из проекта. */
function прочитать(ключ) {
  const подмена = довод('--подмена-' + ключ);
  return fs.readFileSync(подмена || path.join(ПРОЕКТ, ФАЙЛЫ[ключ]), 'utf8');
}

/** Кусок разметки экрана партии: от <section id="экран-игры" до следующего <section. */
function экранПартии(html) {
  const начало = html.indexOf('<section id="экран-игры"');
  if (начало === -1) return '';
  const конец = html.indexOf('<section', начало + 10);
  return html.slice(начало, конец === -1 ? undefined : конец);
}

function проверка() {
  const html = прочитать('html');
  const css = прочитать('css');
  const js = прочитать('js');
  const экран = экранПартии(html);

  console.log('=== Морской бой: общая верхняя строка вместо море-шапки ===');
  проверить(экран.length > 0, 'экран партии #экран-игры найден в разметке');
  проверить(!/море-шапка/.test(html), 'в морской-бой.html класса «море-шапка» нет');
  проверить(!/море-шапка/.test(css), 'в style-морской-бой.css стилей «море-шапка» нет');

  const строка = экран.match(/<div class="верх-игры">[\s\S]*?<\/div>/);
  проверить(Boolean(строка), 'на экране партии есть общая строка .верх-игры');
  const внутри = строка ? строка[0] : '';
  проверить(/<button[^>]*\bdata-назад[^>]*>/.test(внутри), 'в строке есть кнопка data-назад');
  const меню = внутри.match(/<button[^>]*\bdata-меню[^>]*>/);
  проверить(Boolean(меню), 'в строке есть кнопка data-меню');
  проверить(Boolean(меню) && /aria-controls="лист-игры"/.test(меню[0]), 'кнопка data-меню указывает на лист-игры (aria-controls)');
  проверить(/id="лист-игры"/.test(html), 'общий лист «⋯» #лист-игры есть в разметке');
  проверить(/лист-ещё\.js/.test(html), 'страница подключает js/лист-ещё.js');

  // Прежняя поддельная строка «море-верх» убрана совсем, на всех четырёх экранах — общая.
  проверить(!/море-верх/.test(html), 'в морской-бой.html старой строки «море-верх» нет');
  проверить(!/море-верх/.test(css), 'в style-морской-бой.css стилей «море-верх» нет');
  for (const ид of ['экран-лобби', 'море-настройки', 'экран-игры', 'экран-друга']) {
    const н = html.indexOf('<section id="' + ид + '"');
    const кусок = н === -1 ? '' : html.slice(н, html.indexOf('</section>', н));
    const стр = кусок.match(/<div class="верх-игры">[\s\S]*?<\/div>/);
    const с = стр ? стр[0] : '';
    проверить(Boolean(стр) && /\bdata-назад/.test(с) && /\bdata-меню/.test(с) && /aria-controls="лист-игры"/.test(с),
      'экран «' + ид + '»: общая строка .верх-игры с data-назад и data-меню');
    if (ид === 'экран-лобби') проверить(кусок.indexOf('верх-игры') > -1 && кусок.indexOf('верх-игры') < кусок.indexOf('лобби__заголовок'), 'лобби: строка «‹ ⋯» стоит выше заголовка');
  }

  const заголовок = экран.match(/<div class="море-заголовок">[\s\S]*?<\/div>/);
  проверить(Boolean(заголовок), 'под строкой есть .море-заголовок');
  const з = заголовок ? заголовок[0] : '';
  проверить(/<h1>Морской бой<\/h1>/.test(з), 'в заголовке сохранено «Морской бой»');
  проверить(/id="море-правила"/.test(з), 'кнопка «Правила» (#море-правила) на месте');
  проверить(/id="море-сдаться"/.test(з), 'кнопка «Сдаться» (#море-сдаться) на месте');
  for (const ид of ['море-очередь', 'море-счёт-врага', 'море-счёт-свой', 'море-цель']) {
    проверить(html.includes('id="' + ид + '"'), 'счёт и ход не потеряны: #' + ид);
  }

  // Код: обработчики и лист для экрана партии.
  проверить(/querySelectorAll\('\[data-назад\]'\)/.test(js), 'экран-js вешает обработчик на [data-назад]');
  проверить(/querySelectorAll\('\[data-меню\]'\)/.test(js), 'экран-js вешает обработчик на [data-меню]');
  проверить(/экраныСЛистом:\s*\[[^\]]*'экран-игры'/.test(js), 'лист «⋯» подключён для экрана партии');
}

/* ---------- Ломающий прогон: порча КОПИЙ ---------- */

const ПОРЧИ = [
  { заголовок: 'вернули класс «море-шапка» в разметку (копия html)', ключ: 'html',
    порча: т => т.replace('<div class="море-заголовок">', '<div class="море-заголовок море-шапка">'), обязательно: 'класса «море-шапка» нет' },
  { заголовок: 'вернули стиль «море-шапка» в css (копия css)', ключ: 'css',
    порча: т => т + '\n.море-шапка { display: flex; }\n', обязательно: 'стилей «море-шапка» нет' },
  { заголовок: 'пропала общая строка .верх-игры (копия html)', ключ: 'html',
    порча: т => т.replace('<div class="верх-игры">', '<div class="что-то-другое">'), обязательно: 'общая строка .верх-игры' },
  { заголовок: 'у кнопки меню убрали data-меню (копия html)', ключ: 'html',
    порча: т => т.replace(/(<div class="верх-игры">[\s\S]*?)data-меню/, '$1data-x'), обязательно: 'экран «экран-лобби»' },
  { заголовок: 'в лобби вернули поддельную строку «море-верх» (копия html)', ключ: 'html',
    порча: т => т.replace('<section id="экран-лобби" class="экран экран--виден"><div class="верх-игры">', '<section id="экран-лобби" class="экран экран--виден"><div class="море-верх">'), обязательно: 'старой строки «море-верх» нет' },
  { заголовок: 'у экрана «Ваш стол» пропала строка .верх-игры (копия html)', ключ: 'html',
    порча: т => т.replace(/(<section id="экран-друга"[^>]*>)<div class="верх-игры">/, '$1<div class="x">'), обязательно: 'экран «экран-друга»' },
  { заголовок: 'пропала кнопка «Сдаться» (копия html)', ключ: 'html',
    порча: т => т.replace('id="море-сдаться"', 'id="другой"'), обязательно: 'кнопка «Сдаться»' }
];

function ломать() {
  let плохо = 0;
  for (const п of ПОРЧИ) {
    console.log('=== Порча: ' + п.заголовок + ' — обязана покраснеть на «' + п.обязательно + '» ===');
    const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'море-шапка-лом-'));
    try {
      const оригинал = fs.readFileSync(path.join(ПРОЕКТ, ФАЙЛЫ[п.ключ]), 'utf8');
      const испорчен = п.порча(оригинал);
      if (испорчен === оригинал) { console.log('ПРОВАЛ: порча ничего не изменила — образец не найден'); плохо++; continue; }
      const копия = path.join(папка, path.basename(ФАЙЛЫ[п.ключ]));
      fs.writeFileSync(копия, испорчен, 'utf8');
      const прогон = spawnSync(process.execPath, [__filename, '--подмена-' + п.ключ, копия], { encoding: 'utf8' });
      const красные = (прогон.stdout || '').split('\n').filter(с => с.includes('ПЛОХО'));
      const ок = прогон.status === 1 && красные.some(к => к.includes(п.обязательно));
      console.log(ок ? 'ПОКРАСНЕЛ как нужно: ' + красные[0].trim() : 'ПРОВАЛ: не покраснел там, где нужно (код ' + прогон.status + ')');
      if (!ок) плохо++;
    } finally {
      fs.rmSync(папка, { recursive: true, force: true });
    }
  }
  console.log('\nИтого проверок: ' + ПОРЧИ.length + ', провалов: ' + плохо);
  process.exitCode = плохо ? 1 : 0;
}

if (process.argv.includes('--сломать')) ломать();
else {
  проверка();
  console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
  process.exitCode = провалов ? 1 : 0;
}
