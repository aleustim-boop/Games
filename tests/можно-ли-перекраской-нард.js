/* =====================================================================
   НАРДЫ — МОЖНО ЛИ ВЫТЯНУТЬ ПОДСВЕТКУ ОДНОЙ ПЕРЕКРАСКОЙ ДОСКИ.

   Запуск:  node tests/можно-ли-перекраской-нард.js

   ЗАЧЕМ ЭТОТ РАЗБОР ЖИВЁТ В ПРОЕКТЕ. Когда подсветка не берёт порог,
   первое желание — перекрасить доску: так уже делали в шашках, и там
   это помогло. В нардах не помогает, и причина не во вкусе, а в
   арифметике. Чтобы через месяц никто не начал перекрашивать заново,
   счёт лежит здесь и его можно повторить одной командой.

   ЧТО СЧИТАЕМ. Подсветка возможного хода — светлая (золотая) заливка
   поверх пункта. Отношение яркостей растёт вместе с разницей между
   цветом заливки и цветом пункта. Золото само по себе светлое, значит
   на светлом пункте разницы взяться неоткуда — ни при какой густоте.
   Ниже это показано числом: считаем, насколько тёмным обязан стать
   «светлый» пункт, чтобы порог взялся, и что от доски после этого
   останется.

   ВЫВОД, К КОТОРОМУ ЭТОТ СЧЁТ ПРИВЁЛ: перекраской нельзя, нужен тёмный
   контур вокруг подсветки — приём из шашек, где он записан ровно от
   этой беды. Он и сделан; проверяет его tests/мерка-подсветки-нард.js.
   ===================================================================== */

const fs = require('fs');
const path = require('path');

const стиль = fs.readFileSync(path.join(__dirname, '..', 'style-нарды.css'), 'utf8');
const ПОРОГ = 3.0;

function разобратьЦвет(текст) {
  const части = /^#?([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i.exec(String(текст).trim());
  return [parseInt(части[1], 16), parseInt(части[2], 16), parseInt(части[3], 16)];
}
function яркость(цвет) {
  const канал = function (значение) {
    const доля = значение / 255;
    return доля <= 0.03928 ? доля / 12.92 : Math.pow((доля + 0.055) / 1.055, 2.4);
  };
  return 0.2126 * канал(цвет[0]) + 0.7152 * канал(цвет[1]) + 0.0722 * канал(цвет[2]);
}
function отношение(а, б) {
  const пара = [яркость(а), яркость(б)].sort(function (х, у) { return у - х; });
  return (пара[0] + 0.05) / (пара[1] + 0.05);
}
function смешать(верх, низ, доля) {
  return [0, 1, 2].map(function (i) { return Math.round(верх[i] * доля + низ[i] * (1 - доля)); });
}

/* Цвета читаем из оформления, а не переписываем сюда: вторая копия
   однажды разошлась бы с настоящей. */
function телоДоски(имя) {
  const правило = имя === 'дерево'
    ? /html,\s*html\[data-доска="дерево"\]\s*\{([\s\S]*?)\}/.exec(стиль)
    : new RegExp('html\\[data-доска="' + имя + '"\\]\\s*\\{([\\s\\S]*?)\\}').exec(стиль);
  return правило[1];
}
function переменная(тело, имя) {
  return разобратьЦвет(new RegExp('--' + имя + '\\s*:\\s*(#[0-9a-fA-F]{6})').exec(тело)[1]);
}

const ДОСКИ = ['дерево', 'камень', 'классика'];
const ЗОЛОТО = переменная(телоДоски('дерево'), 'подсветка');

console.log('=== Можно ли вытянуть подсветку нард одной перекраской доски ===');
console.log('Цвет подсветки берём из оформления: #' +
  ЗОЛОТО.map(function (з) { return з.toString(16).padStart(2, '0'); }).join('') + '\n');

console.log('1. Насколько тёмным обязан быть пункт, чтобы золотая заливка');
console.log('   взяла порог ' + ПОРОГ.toFixed(1) + '. Проверяем по серой шкале:');
const пределы = {};
for (const густота of [0.42, 0.6, 0.8, 1.0]) {
  let предел = null;
  for (let значение = 0; значение <= 255; значение++) {
    const пункт = [значение, значение, значение];
    if (отношение(смешать(ЗОЛОТО, пункт, густота), пункт) >= ПОРОГ) предел = значение;
  }
  пределы[густота] = предел;
  console.log('   заливка ' + Math.round(густота * 100) + '%: пункт должен быть темнее ' +
    предел + ' из 255');
}
console.log('\n   А светлые пункты сейчас вот такие:');
for (const имя of ДОСКИ) {
  const светлый = переменная(телоДоски(имя), 'пункт-светлый');
  console.log('   ' + имя + ': ' + Math.round((светлый[0] + светлый[1] + светлый[2]) / 3) + ' из 255');
}

console.log('\n2. Допустим, перекрасили. Останется ли доска доской?');
console.log('   Светлый пункт станет ' + пределы[0.42] + ' из 255. Сравним его с тёмным:');
let сливаются = 0;
for (const имя of ДОСКИ) {
  const тёмный = переменная(телоДоски(имя), 'пункт-тёмный');
  const о = отношение([пределы[0.42], пределы[0.42], пределы[0.42]], тёмный);
  if (о < 1.6) сливаются++;
  console.log('   ' + имя + ': светлый против тёмного — ' + о.toFixed(2) +
    (о < 1.6 ? '  (сливаются, чередования не видно)' : '  (различить можно)'));
}

console.log('\n3. ВЫВОД');
if (сливаются === ДОСКИ.length) {
  console.log('   Перекраской нельзя. Чтобы золотая заливка стала заметна,');
  console.log('   светлый треугольник обязан перестать быть светлым — и тогда');
  console.log('   сливается с тёмным на всех трёх досках. Даже сплошная');
  console.log('   заливка без прозрачности упирается в ' + пределы[1.0] + ' из 255.');
  console.log('   Светлое на светлом не даёт трёхкратной разницы яркости');
  console.log('   ни при какой густоте — это свойство самой меры, а не вкуса.');
  console.log('\n   Поэтому светлые пункты вытягивает тёмный контур вокруг');
  console.log('   подсветки, а не перекраска. Проверяет его');
  console.log('   tests/мерка-подсветки-нард.js.');
} else {
  console.log('   Цвета изменились: теперь перекраска может сработать.');
  console.log('   Пересчитайте вместе с меркой подсветки.');
}
