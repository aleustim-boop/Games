/* =====================================================================
   КАРТОЧКА «РАЗДАЧА ДНЯ» В ЛОББИ ДУРАКА (этап Б2 штаб/план-учёт-и-раздача.md)

   Что проверяет. Поднимает НАСТОЯЩИЙ игры/дурак/game.js в песочнице vm поверх
   документа, собранного из НАСТОЯЩЕГО index.html (узлы — из общего
   tests/поддельный-браузер.js, разметку разбирает маленький разборщик
   ниже). Чего в разметке нет — того нет и в песочнице: «узел есть»
   здесь значит «он есть в index.html», а не «подделка создала его сама».

     1) в index.html карточка «карточка-раздачи-дня» стоит в блоке входов
        лобби, сразу за «Играть с ботами», тем же каркасом (карточка-входа,
        модификатор карточка-входа--раздача, подпись внутри __текст);
     2) не играли — подпись «Одна раздача для всех», класса «сыграна» нет;
        нажатие начинает раздачу дня (раздачаДняИдёт = сегодня);
     3) в daily_durak сегодняшняя запись — карточка «сыграна», выключена,
        подпись «Победа · 14 ходов · 3-е место»; нажатие ничего
        не начинает;
     4) запись появилась, пока лобби было скрыто, — показ лобби освежает
        карточку (вызов в показатьЭкран);
     5) гость (без места, только «сыграли») — «· сыграли 40».

   Запуск:
       node tests/раздача-дня-карточка.js                 — обычный прогон
       node tests/раздача-дня-карточка.js --game=<путь>   — прогон на чужой
            копии игры/дурак/game.js (для ломающего запуска руками)
       node tests/раздача-дня-карточка.js --сломать       — сам делает копию
            игры/дурак/game.js во временной папке ОС без «наКнопку(КАРТОЧКА_…)»,
            гоняет проверки на ней и требует провала. Настоящий файл
            не трогается.
   Итог: «Итого проверок: N, провалов: M», при провале — код 1.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const vm = require('vm');
const подделка = require('./поддельный-браузер.js');

const КОРЕНЬ = path.join(__dirname, '..');
const ПУТЬ_ИГРЫ = path.join(КОРЕНЬ, 'игры', 'дурак', 'game.js');
const ПУТЬ_РАЗМЕТКИ = path.join(КОРЕНЬ, 'index.html');
const ИД_КАРТОЧКИ = 'карточка-раздачи-дня';
const СЕГОДНЯ = '2026-10-03';

/* ---------------------------------------------------------------------
   Разметка → честные узлы поддельного документа
   --------------------------------------------------------------------- */

const ПУСТЫЕ_ТЕГИ = new Set(['area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'source', 'track', 'wbr']);

/** Разобрать атрибуты тега: имя="значение", имя='значение', имя=значение, голое имя. */
function атрибутыТега(текст) {
  const итог = [];
  const образец = /([^\s=\/>]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+)))?/g;
  let м;
  while ((м = образец.exec(текст)) !== null) {
    const значение = м[2] !== undefined ? м[2] : (м[3] !== undefined ? м[3] : (м[4] !== undefined ? м[4] : ''));
    итог.push({ имя: м[1], значение: значение });
  }
  return итог;
}

/**
 * Разложить html страницы в body поддельного документа. Скрипты, стили
 * и комментарии выбрасываем: скрипты песочница запускает сама, по одному.
 */
function разметкаВДокумент(html, документ) {
  const чистый = html
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<script\b[\s\S]*?<\/script>/gi, '')
    .replace(/<style\b[\s\S]*?<\/style>/gi, '')
    .replace(/<!doctype[^>]*>/i, '');
  const стопка = [документ.body];
  const образец = /<(\/?)([a-zA-Z][\w:-]*)((?:\s+[^\s=\/>]+(?:\s*=\s*(?:"[^"]*"|'[^']*'|[^\s>]+))?)*)\s*(\/?)>|([^<]+)/g;
  let м;
  while ((м = образец.exec(чистый)) !== null) {
    const верх = стопка[стопка.length - 1];
    if (м[5] !== undefined) {
      верх.appendChild(документ.createTextNode(м[5]));
      continue;
    }
    const тег = м[2].toLowerCase();
    if (тег === 'html' || тег === 'head' || тег === 'body') continue;
    if (м[1] === '/') {
      for (let i = стопка.length - 1; i > 0; i--) {
        if (стопка[i].tagName === тег.toUpperCase()) { стопка.length = i; break; }
      }
      continue;
    }
    const узел = документ.createElement(тег);
    for (const а of атрибутыТега(м[3] || '')) {
      узел.setAttribute(а.имя, а.значение);
      if (а.имя === 'disabled') узел.disabled = true;
      if (а.имя === 'hidden') узел.hidden = true;
    }
    верх.appendChild(узел);
    if (м[4] !== '/' && !ПУСТЫЕ_ТЕГИ.has(тег)) стопка.push(узел);
  }
}

/** Поддельный звук: game.js щёлкает на нажатиях, песочнице нужен только вид. */
function ПоддельныйЗвук() {
  return {
    state: 'running', currentTime: 0, resume() { return Promise.resolve(); },
    createOscillator() { return { connect() {}, start() {}, stop() {}, type: '', frequency: { setValueAtTime() {}, exponentialRampToValueAtTime() {} } }; },
    createGain() { return { connect() {}, gain: { setValueAtTime() {}, exponentialRampToValueAtTime() {}, linearRampToValueAtTime() {} } }; },
    destination: {}
  };
}

/**
 * Поднять index.html + игры/дурак/game.js. опции: { путьИгры, память (записи
 * localStorage до запуска), telegram (добавки к WebApp — тогда игра
 * «в Telegram»), доПуска(сцена) — подложить что-то в окно до game.js }.
 */
function поднятьИгру(опции) {
  const о = опции || {};
  const документ = подделка.сделатьДокумент();
  разметкаВДокумент(fs.readFileSync(ПУТЬ_РАЗМЕТКИ, 'utf8'), документ);
  const память = подделка.сделатьПамять(false);
  for (const ключ of Object.keys(о.память || {})) память.setItem(ключ, о.память[ключ]);
  const часы = подделка.поддельныеЧасы();
  часы.поставить(Number(СЕГОДНЯ.slice(0, 4)), Number(СЕГОДНЯ.slice(5, 7)), Number(СЕГОДНЯ.slice(8, 10)));
  const сцена = подделка.поднять('/* пусто: game.js запускаем ниже, после подкладки */', {
    документ: документ, память: память, часы: часы, telegram: о.telegram, имяФайла: 'пусто.js'
  });
  сцена.окно.AudioContext = ПоддельныйЗвук;
  сцена.песочница.AudioContext = ПоддельныйЗвук;
  if (typeof о.доПуска === 'function') о.доПуска(сцена);
  vm.runInContext(fs.readFileSync(о.путьИгры || ПУТЬ_ИГРЫ, 'utf8'), сцена.песочница, { filename: 'игры/дурак/game.js' });
  return сцена;
}

/* ---------------------------------------------------------------------
   Проверки
   --------------------------------------------------------------------- */

function прогнать(путьИгры) {
  const строки = [];
  let провалов = 0;
  const проверить = function (условие, слова) {
    строки.push((условие ? 'ок    — ' : 'ПЛОХО — ') + слова);
    if (!условие) провалов++;
  };
  const подписьКарточки = function (карточка) {
    const п = карточка ? карточка.querySelector('.карточка-входа__подпись') : null;
    return п ? п.textContent : null;
  };

  /* 1) разметка */
  {
    const документ = подделка.сделатьДокумент();
    разметкаВДокумент(fs.readFileSync(ПУТЬ_РАЗМЕТКИ, 'utf8'), документ);
    const карточка = документ.getElementById(ИД_КАРТОЧКИ);
    проверить(Boolean(карточка), '1) в index.html есть узел «' + ИД_КАРТОЧКИ + '»');
    const входы = карточка ? карточка.closest('.лобби__входы') : null;
    проверить(Boolean(входы), '1) карточка лежит в блоке входов лобби (.лобби__входы)');
    проверить(Boolean(карточка) && карточка.tagName === 'BUTTON', '1) карточка — кнопка (нажимается пальцем)');
    проверить(Boolean(карточка) && карточка.classList.contains('карточка-входа') && карточка.classList.contains('карточка-входа--раздача'),
      '1) классы «карточка-входа» и «карточка-входа--раздача»');
    const боты = документ.getElementById('лобби-боты');
    const соседи = входы ? входы.children : [];
    const гдеБоты = соседи.indexOf(боты);
    проверить(гдеБоты !== -1 && соседи[гдеБоты + 1] === карточка, '1) стоит сразу за «Играть с ботами» (лобби-боты)');
    проверить(Boolean(карточка && карточка.querySelector('.карточка-входа__текст .карточка-входа__подпись')),
      '1) подпись — внутри узла «карточка-входа__текст»');
    проверить(Boolean(карточка && карточка.querySelector('.карточка-входа__значок')), '1) есть гнездо значка «карточка-входа__значок»');
  }

  /* 2) не играли: зовёт, нажатие начинает раздачу дня */
  try {
    const сцена = поднятьИгру({ путьИгры: путьИгры });
    const карточка = сцена.документ.getElementById(ИД_КАРТОЧКИ);
    проверить(подписьКарточки(карточка) === 'Одна раздача для всех', '2) не играли — подпись «Одна раздача для всех» (вышло: ' + JSON.stringify(подписьКарточки(карточка)) + ')');
    проверить(Boolean(карточка) && !карточка.classList.contains('сыграна') && карточка.disabled === false, '2) не играли — нет класса «сыграна», карточка нажимается');
    проверить(сцена.спросить('раздачаДняИдёт') === null, '2) до нажатия раздача дня не идёт');
    if (карточка) карточка.click();
    const идёт = сцена.спросить('раздачаДняИдёт');
    проверить(идёт === СЕГОДНЯ, '2) нажатие на карточку начинает раздачу дня (раздачаДняИдёт: ' + JSON.stringify(идёт) + ')');
  } catch (сбой) {
    проверить(false, '2) game.js поднимается и карточка нажимается без падения: ' + сбой.message);
  }

  /* 3) сыграли сегодня: «сыграна», выключена, нажатие ничего не начинает */
  try {
    const запись = JSON.stringify({ дата: СЕГОДНЯ, исход: 'победа', ходов: 14, место: 3 });
    const сцена = поднятьИгру({ путьИгры: путьИгры, память: { daily_durak: запись } });
    const карточка = сцена.документ.getElementById(ИД_КАРТОЧКИ);
    проверить(Boolean(карточка) && карточка.classList.contains('сыграна'), '3) запись в daily_durak — карточка с классом «сыграна»');
    проверить(Boolean(карточка) && карточка.disabled === true, '3) сыгранная карточка выключена (disabled)');
    проверить(подписьКарточки(карточка) === 'Победа · 14 ходов · 3-е место',
      '3) подпись «Победа · 14 ходов · 3-е место» (вышло: ' + JSON.stringify(подписьКарточки(карточка)) + ')');
    if (карточка) карточка.click();   // подделка не глушит нажатие на выключенную кнопку — защита должна быть в коде
    проверить(сцена.спросить('раздачаДняИдёт') === null, '3) нажатие на сыгранную карточку раздачу не начинает');
    const вчера = JSON.stringify({ дата: '2026-10-02', исход: 'поражение', ходов: 9, место: 5 });
    сцена.память.setItem('daily_durak', вчера);
    сцена.спросить("показатьЭкран('экран-лобби')");
    проверить(!карточка.classList.contains('сыграна') && подписьКарточки(карточка) === 'Одна раздача для всех',
      '3) вчерашняя запись не считается: после показа лобби карточка снова зовёт');
  } catch (сбой) {
    проверить(false, '3) сыгранная раздача поднимается без падения: ' + сбой.message);
  }

  /* 4) запись появилась, пока лобби было скрыто: показ лобби освежает */
  try {
    const сцена = поднятьИгру({ путьИгры: путьИгры });
    const карточка = сцена.документ.getElementById(ИД_КАРТОЧКИ);
    сцена.память.setItem('daily_durak', JSON.stringify({ дата: СЕГОДНЯ, исход: 'поражение', ходов: 23 }));
    сцена.спросить("показатьЭкран('экран-лобби')");
    проверить(Boolean(карточка) && карточка.classList.contains('сыграна'), '4) показ лобби освежает карточку — «сыграна»');
    проверить(подписьКарточки(карточка) === 'Поражение · 23 хода',
      '4) без ответа сервера — итог без места (вышло: ' + JSON.stringify(подписьКарточки(карточка)) + ')');
  } catch (сбой) {
    проверить(false, '4) показ лобби без падения: ' + сбой.message);
  }

  /* 5) гость: места нет, есть «сыграли» из сводки */
  try {
    const запись = JSON.stringify({ дата: СЕГОДНЯ, исход: 'поражение', ходов: 23, сыграли: 40 });
    const сцена = поднятьИгру({ путьИгры: путьИгры, память: { daily_durak: запись } });
    const карточка = сцена.документ.getElementById(ИД_КАРТОЧКИ);
    проверить(подписьКарточки(карточка) === 'Поражение · 23 хода · сыграли 40',
      '5) гость — «· сыграли 40» без места (вышло: ' + JSON.stringify(подписьКарточки(карточка)) + ')');
  } catch (сбой) {
    проверить(false, '5) гостевая запись без падения: ' + сбой.message);
  }

  return { строки: строки, провалов: провалов };
}

function довод(имя) {
  const найдено = process.argv.find(function (с) { return с.indexOf('--' + имя + '=') === 0; });
  return найдено ? найдено.slice(имя.length + 3) : '';
}

function напечатать(итог) {
  итог.строки.forEach(function (с) { console.log('  ' + с); });
  console.log('\nИтого проверок: ' + итог.строки.length + ', провалов: ' + итог.провалов);
}

if (require.main === module) {
  if (process.argv.indexOf('--сломать') !== -1) {
    const оригинал = fs.readFileSync(ПУТЬ_ИГРЫ, 'utf8');
    let вырезано = 0;
    const испорченный = оригинал.replace(/наКнопку\(КАРТОЧКА_РАЗДАЧИ_ДНЯ, начатьРаздачуДня\);/g, function () {
      вырезано++;
      return '/* ломающий прогон: нажатие карточки не привязано */';
    });
    if (вырезано === 0) {
      console.log('ПЛОХО — порча не применилась: в игры/дурак/game.js нет «наКнопку(КАРТОЧКА_РАЗДАЧИ_ДНЯ, начатьРаздачуДня);». Обновите порчу.');
      process.exit(1);
    }
    const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'раздача-дня-карточка-'));
    const копия = path.join(папка, 'game.js');
    fs.writeFileSync(копия, испорченный, 'utf8');
    console.log('ЛОМАЮЩИЙ ПРОГОН: копия без наКнопку — ' + копия + ' (вырезано: ' + вырезано + ')\n');
    const итог = прогнать(копия);
    try { fs.unlinkSync(копия); fs.rmdirSync(папка); } catch (сбой) { /* уборка временной папки не влияет на итог */ }
    напечатать(итог);
    const поймали = итог.строки.some(function (с) { return с.indexOf('ПЛОХО — 2) нажатие на карточку начинает раздачу дня') === 0; });
    console.log(поймали ? '\nПорча поймана: проверка покраснела, как должна.' : '\nПРОВЕРКА СЛЕПАЯ: порча не поймана.');
    process.exit(поймали ? 0 : 1);
  }
  const путь = довод('game') || ПУТЬ_ИГРЫ;
  if (путь !== ПУТЬ_ИГРЫ) console.log('Прогон на копии игры/дурак/game.js: ' + путь + '\n');
  const итог = прогнать(путь);
  напечатать(итог);
  process.exit(итог.провалов > 0 ? 1 : 0);
}

module.exports = { поднятьИгру: поднятьИгру, разметкаВДокумент: разметкаВДокумент, СЕГОДНЯ: СЕГОДНЯ, ИД_КАРТОЧКИ: ИД_КАРТОЧКИ };
