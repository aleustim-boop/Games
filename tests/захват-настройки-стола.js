function мир(безСети) {
  const документ = сделатьДокумент();
  собратьРазметку(исходникСтраницы, документ);
  документ.querySelectorAll('dialog').forEach(окно => {
    окно.open = false;
    окно.showModal = () => { окно.open = true; };
    окно.close = () => { окно.open = false; };
  });
  const р = поднять('', { память: сделатьПамять(false), документ: документ });
  const сеть = сделатьСеть();
  if (!безСети) р.окно.Сеть = сеть;
  р.окно.Телеграм = {
    показатьСтрелку: () => true, кнопкаНастроек: () => true, отклик: () => {},
    имяИгрока: () => 'Аня', вибрацияДоступна: () => false, вибрацияВключена: () => false, включитьВибрацию: () => {}
  };
  for (const часть of ЧАСТИ_ДО_МОДУЛЯ) {
    vm.runInContext(fs.readFileSync(require('./пути-проекта.js').путь(часть, КОРЕНЬ), 'utf8'), р.песочница, { filename: '' + require('./пути-проекта.js').отКорня(часть) });
  }
  vm.runInContext(исходникМодуля, р.песочница, { filename: ФАЙЛ_МОДУЛЯ });
  const м = { окно: р.окно, документ: документ, сеть: сеть, узел: id => документ.getElementById(id) };
  м.модуль = р.окно.ЗахватОнлайн;
  м.экран = р.окно.ЗахватЭкран;
  if (!м.модуль) throw new Error('Модуль не поставил window.ЗахватОнлайн');
  м.кнопки = id => (м.узел(id) ? м.узел(id).querySelectorAll('button') : []);
  м.отмеченные = id => м.кнопки(id).filter(к => к.getAttribute('aria-checked') === 'true').map(к => к.getAttribute('data-значение'));
  м.нажатьПилюлю = (id, значение) => {
    const кнопка = м.кнопки(id).find(к => к.getAttribute('data-значение') === значение);
    if (!кнопка) throw new Error('В группе ' + id + ' нет кнопки ' + значение);
    кнопка.click();
  };
  // «Создать игру» слушается в фазе захвата и гасит событие — нужен полный объект события.
  м.создать = () => {
    const кнопка = м.узел('кнопка-создать-игру');
    if (!кнопка) throw new Error('Нет кнопки «Создать игру»');
    кнопка.dispatchEvent({ type: 'click', target: кнопка, preventDefault() {}, stopPropagation() {}, stopImmediatePropagation() {} });
  };
  м.последнийСтол = () => сеть.столы[сеть.столы.length - 1] || null;
  м.сообщение = () => {
    const у = м.узел('сообщение-друга');
    return у && !у.classList.contains('скрыт') ? у.textContent : '';
  };
  return м;
}

/* ---------- 1. группы построены, по умолчанию — как в ТЗ ---------- */

function проверитьГруппы() {
  const м = мир();
  for (const г of ГРУППЫ) {
    const узел = м.узел(г.id);
    if (!проверка('группы: узел #' + г.id + ' есть в разметке', !!узел)) continue;
    проверка('группы: #' + г.id + ' — radiogroup внутри #экран-друга',
      узел.getAttribute('role') === 'radiogroup' && !!узел.closest('#экран-друга'));
    const кнопки = м.кнопки(г.id);
    проверка('группы: в #' + г.id + ' кнопок ' + г.значения.length, кнопки.length === г.значения.length, 'нашлось ' + кнопки.length);
    проверка('группы: значения #' + г.id, кнопки.map(к => к.getAttribute('data-значение')).join(',') === г.значения.join(','),
      кнопки.map(к => к.getAttribute('data-значение')).join(','));
    проверка('группы: слова #' + г.id, кнопки.map(к => к.textContent).join(',') === г.слова.join(','), кнопки.map(к => к.textContent).join(','));
    проверка('группы: кнопки #' + г.id + ' — radio', кнопки.length > 0 && кнопки.every(к => к.getAttribute('role') === 'radio' && к.getAttribute('type') === 'button'));
    проверка('группы: по умолчанию в #' + г.id + ' отмечено ' + г.обычно, м.отмеченные(г.id).join(',') === г.обычно, м.отмеченные(г.id).join(','));
  }
  // Группа раундов — после времени, перед подписью (порядок ТЗ 8.3).
  const панель = м.узел('кнопка-создать-игру') && м.узел('кнопка-создать-игру').parentNode;
  const порядок = панель ? панель.querySelectorAll('[id]').map(у => у.id) : [];
  const где = id => порядок.indexOf(id);
  проверка('группы: порядок — мест, боты, время, раунды, подпись',
    где('захват-онлайн-число') !== -1 && где('захват-онлайн-число') < где('захват-онлайн-уровень') && где('захват-онлайн-уровень') < где('захват-онлайн-время')
      && где('захват-онлайн-время') < где('захват-онлайн-раунды') && где('захват-онлайн-раунды') < где('захват-онлайн-подпись'),
    порядок.join(' '));
  // Видимая строка-подпись над каждой группой: у ряда 2…6 её раньше не было (замечание смотрителя).
  for (const [id, слова] of [['захват-онлайн-число', 'Мест за столом'], ['захват-онлайн-раунды', 'Раундов']]) {
    const обёртка = м.узел(id) && м.узел(id).parentNode;
    const строка = обёртка && /(^|\s)захват-выбор-параметра(\s|$)/.test(обёртка.className || '') ? обёртка.querySelector('strong') : null;
    проверка('группы: у #' + id + ' строка «' + слова + '»', !!строка && строка.textContent === слова, строка ? строка.textContent : 'нет обёртки или строки');
  }
}

/* ---------- 2–3. нажатие меняет отметку, настройкиСтола отдаёт выбранное ---------- */

function проверитьНажатия() {
  const м = мир();
  for (const г of ГРУППЫ) {
    for (const значение of г.значения) {
      м.нажатьПилюлю(г.id, значение);
      проверка('нажатие: в #' + г.id + ' после «' + значение + '» отмечена только она', м.отмеченные(г.id).join(',') === значение,
        м.отмеченные(г.id).join(','));
      const н = м.модуль.настройкиСтола();
      проверка('нажатие: настройкиСтола().' + г.поле + ' = ' + значение, String(н[г.поле]) === значение, JSON.stringify(н));
    }
  }
  м.нажатьПилюлю('захват-онлайн-число', '5');
  м.нажатьПилюлю('захват-онлайн-уровень', 'лёгкий');
  м.нажатьПилюлю('захват-онлайн-время', '40');
  м.нажатьПилюлю('захват-онлайн-раунды', '10');
  const н = м.модуль.настройкиСтола();
  проверка('настройки: выбранное целиком', н.мест === 5 && н.уровеньБотов === 'лёгкий' && н.лимитСекундНаХод === 40 && н.раундовЗахвата === 10,
    JSON.stringify(н));
  проверка('настройки: числа — числами', typeof н.мест === 'number' && typeof н.лимитСекундНаХод === 'number' && typeof н.раундовЗахвата === 'number');
  проверка('настройки: мусор не принят', м.модуль.выбрать('мест', 7) === false && м.модуль.выбрать('лимитСекундНаХод', 30) === false
    && м.модуль.выбрать('уровеньБотов', 'злой') === false && м.модуль.выбрать('нет-такого', 1) === false && м.модуль.настройкиСтола().мест === 5);
}

/* ---------- 4. тело создания стола несёт выбор ---------- */

async function проверитьТелоСоздания() {
  const м = мир();
  м.создать();
  await отпуститьВсё();
  const обычный = м.последнийСтол();
  проверка('создание: «Создать игру» дошла до создатьКомнату', !!обычный);
  if (обычный) {
    проверка('создание: по умолчанию — 4 · обычный · 60 · 15',
      обычный.мест === 4 && обычный.уровеньБотов === 'обычный' && обычный.лимитСекундНаХод === 60 && обычный.раундовЗахвата === 15, JSON.stringify(обычный));
    проверка('создание: стол — компания и открытый', обычный.компанией === true && обычный.открытый === true, JSON.stringify(обычный));
  }
  const наборы = [
    { число: '6', уровень: 'сложный', время: '40', раунды: '20' },
    { число: '2', уровень: 'лёгкий', время: '60', раунды: '10' }
  ];
  for (const н of наборы) {
    м.нажатьПилюлю('захват-онлайн-число', н.число);
    м.нажатьПилюлю('захват-онлайн-уровень', н.уровень);
    м.нажатьПилюлю('захват-онлайн-время', н.время);
    м.нажатьПилюлю('захват-онлайн-раунды', н.раунды);
    const до = м.сеть.столы.length;
    м.создать();
    await отпуститьВсё();
    const стол = м.последнийСтол();
    проверка('создание: набор ' + JSON.stringify(н) + ' — ушёл один стол', м.сеть.столы.length === до + 1);
    проверка('создание: мест ' + н.число, !!стол && стол.мест === Number(н.число), JSON.stringify(стол));
    проверка('создание: уровеньБотов ' + н.уровень, !!стол && стол.уровеньБотов === н.уровень, JSON.stringify(стол));
    проверка('создание: лимитСекундНаХод ' + н.время, !!стол && стол.лимитСекундНаХод === Number(н.время), JSON.stringify(стол));
    проверка('создание: раундовЗахвата ' + н.раунды, !!стол && стол.раундовЗахвата === Number(н.раунды), JSON.stringify(стол));
  }
}

