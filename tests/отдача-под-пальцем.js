'use strict';

/* =====================================================================
   ОТДАЧА ПОД ПАЛЬЦЕМ — проверка двери window.Телеграм.отклик.

   Что проверяем (всё без браузера, на поддельном браузере из
   tests/поддельный-браузер.js):

     1. каждый вид отклика зовёт у Telegram именно тот метод, который
        обещан в js/telegram.js (выбор — selectionChanged, карта — удар
        средней силы, победа — весть об успехе и так далее);
     2. без Telegram дверь молчит и ничего не роняет — ни ошибки,
        ни строчки в консоли: игра открывается и в обычном браузере;
     3. старый Telegram (версия ниже 6.1, где вибрации нет вовсе) —
        тоже молчание, а не ругань в консоль;
     4. дверь не частит: два одинаковых отклика подряд дают одну
        вибрацию, а через паузу — снова работают;
     5. победа не съедается паузой от только что легшей карты
        (у вестей своя дорожка);
     6. выключатель работает и переживает перезагрузку страницы;
     7. незнакомый вид отклика не роняет игру, а один раз подсказывает
        разработчику в консоль.

   Запуск:  node tests/отдача-под-пальцем.js
   Ответ:   «всё хорошо» и код 0, либо список бед и код 1.
   ===================================================================== */

const { поднятьTelegramJS, сделатьПамять, поддельныеЧасы } = require('./поддельный-браузер.js');

const беды = [];
function надо(условие, что) {
  if (!условие) беды.push(что);
}

/* Поддельный HapticFeedback: записывает всё, о чём его просили. */
function сделатьОтдачу() {
  const просьбы = [];
  return {
    просьбы: просьбы,
    impactOccurred: function (сила) { просьбы.push('удар:' + сила); },
    notificationOccurred: function (исход) { просьбы.push('весть:' + исход); },
    selectionChanged: function () { просьбы.push('выбор'); }
  };
}

/* Поднять js/telegram.js так, как он выглядит внутри Telegram нужной версии. */
function поднятьСТелеграмом(настройки) {
  const н = настройки || {};
  const отдача = н.отдача === null ? null : сделатьОтдачу();
  const версия = н.версия || '7.10';
  const часы = н.часы || поддельныеЧасы();
  const память = н.память || сделатьПамять(false);
  const стенд = поднятьTelegramJS({
    память: память,
    часы: часы,
    telegram: {
      version: версия,
      isVersionAtLeast: function (нужна) {
        const было = String(версия).split('.').map(Number);
        const надоТак = String(нужна).split('.').map(Number);
        for (let i = 0; i < Math.max(было.length, надоТак.length); i++) {
          const а = было[i] || 0;
          const б = надоТак[i] || 0;
          if (а !== б) return а > б;
        }
        return true;
      },
      HapticFeedback: отдача || undefined
    }
  });
  return { дверь: стенд.окно.Телеграм, отдача: отдача, часы: часы, память: память, стенд: стенд };
}

// ---------------------------------------------------------------------------
// 1. Каждый вид зовёт свой метод Telegram
// ---------------------------------------------------------------------------

{
  const ожидаем = [
    ['выбор', 'выбор'],
    ['лёгкий', 'удар:light'],
    ['карта', 'удар:medium'],
    ['взятка', 'удар:heavy'],
    ['победа', 'весть:success'],
    ['проигрыш', 'весть:error'],
    ['нельзя', 'весть:warning']
  ];
  for (const [вид, просьба] of ожидаем) {
    // Каждый вид проверяем на своём стенде, чтобы паузы не мешали
    const с = поднятьСТелеграмом();
    const сработало = с.дверь.отклик(вид);
    надо(сработало === true, 'вид «' + вид + '»: дверь должна была сказать «да»');
    надо(с.отдача.просьбы.join(',') === просьба,
      'вид «' + вид + '»: ждали «' + просьба + '», а попросили «' + с.отдача.просьбы.join(',') + '»');
  }
}

// ---------------------------------------------------------------------------
// 2. Без Telegram — молчание, а не поломка
// ---------------------------------------------------------------------------

{
  const стенд = поднятьTelegramJS({});   // окно без window.Telegram вовсе
  const дверь = стенд.окно.Телеграм;
  надо(typeof дверь.отклик === 'function', 'дверь «отклик» должна быть и вне Telegram');
  let упало = null;
  let ответ = null;
  try {
    ответ = дверь.отклик('карта');
  } catch (ошибка) {
    упало = ошибка;
  }
  надо(упало === null, 'вне Telegram отклик не должен падать, а он бросил: ' + упало);
  надо(ответ === false, 'вне Telegram отклик должен вернуть «нет»');
  надо(стенд.предупреждения.length === 0,
    'вне Telegram консоль должна молчать, а там: ' + стенд.предупреждения.join(' | '));
  надо(стенд.ошибкиКонсоли.length === 0,
    'вне Telegram красных строк быть не должно, а там: ' + стенд.ошибкиКонсоли.join(' | '));
}

// ---------------------------------------------------------------------------
// 3. Старый Telegram (до 6.1) — тоже молчание
// ---------------------------------------------------------------------------

{
  const с = поднятьСТелеграмом({ версия: '6.0' });
  const ответ = с.дверь.отклик('карта');
  надо(ответ === false, 'в Telegram 6.0 вибрации нет — ждали «нет»');
  надо(с.отдача.просьбы.length === 0, 'в Telegram 6.0 просить вибрацию нельзя вовсе');
  надо(с.стенд.предупреждения.length === 0, 'старый Telegram не повод ругаться в консоль');
}

// ---------------------------------------------------------------------------
// 4. Не частим: два подряд — одна вибрация, через паузу — снова работает
// ---------------------------------------------------------------------------

{
  const с = поднятьСТелеграмом();
  надо(с.дверь.отклик('выбор') === true, 'первый выбор должен сработать');
  надо(с.дверь.отклик('выбор') === false, 'второй выбор сразу же — это дребезг, его глушим');
  надо(с.отдача.просьбы.length === 1, 'от двух выборов подряд ждали одну просьбу к Telegram');

  с.часы.прошло(200);   // подождали дольше паузы выбора (120 мс)
  надо(с.дверь.отклик('выбор') === true, 'после паузы выбор снова должен работать');
  надо(с.отдача.просьбы.length === 2, 'после паузы просьб должно стать две');
}

{
  // Удары чаще выборов: своя, более короткая пауза (50 мс)
  const с = поднятьСТелеграмом();
  надо(с.дверь.отклик('карта') === true, 'первая карта должна сработать');
  с.часы.прошло(60);
  надо(с.дверь.отклик('карта') === true, 'вторая карта через 60 мс — это уже не дребезг');
  надо(с.отдача.просьбы.length === 2, 'две карты с промежутком — две вибрации');
}

// ---------------------------------------------------------------------------
// 5. Победа не съедается паузой от только что легшей карты
// ---------------------------------------------------------------------------

{
  const с = поднятьСТелеграмом();
  с.дверь.отклик('карта');
  const победа = с.дверь.отклик('победа');   // сразу же, без всякой паузы
  надо(победа === true, 'победа обязана сработать даже сразу после карты');
  надо(с.отдача.просьбы.join(',') === 'удар:medium,весть:success',
    'ждали карту и победу, а попросили: ' + с.отдача.просьбы.join(','));
}

// ---------------------------------------------------------------------------
// 6. Выключатель: работает и переживает перезагрузку страницы
// ---------------------------------------------------------------------------

{
  const память = сделатьПамять(false);
  const с = поднятьСТелеграмом({ память: память });
  надо(с.дверь.вибрацияВключена() === true, 'по умолчанию вибрация включена');

  с.дверь.включитьВибрацию(false);
  надо(с.дверь.вибрацияВключена() === false, 'после выключения дверь должна отвечать «нет»');
  надо(с.дверь.отклик('победа') === false, 'выключенная вибрация не должна срабатывать');
  надо(с.отдача.просьбы.length === 0, 'выключенная вибрация не должна дёргать Telegram');

  const ключи = память.ключи();
  надо(ключи.indexOf('haptics') !== -1, 'настройка должна лечь под латинский ключ «haptics», а легли: ' + ключи.join(','));
  for (const ключ of ключи) {
    надо(/^[A-Za-z0-9_-]+$/.test(ключ), 'ключ «' + ключ + '» не латинский — облако такой отвергает');
  }

  // Перезагрузка страницы: тот же ящик памяти, файл поднят заново
  const снова = поднятьСТелеграмом({ память: память });
  надо(снова.дверь.вибрацияВключена() === false, 'после перезагрузки выключенная вибрация должна остаться выключенной');
  надо(снова.дверь.отклик('карта') === false, 'после перезагрузки выключенная вибрация молчит');

  снова.дверь.включитьВибрацию(true);
  надо(снова.дверь.вибрацияВключена() === true, 'включить обратно тоже надо уметь');
  надо(снова.дверь.отклик('карта') === true, 'включённая обратно вибрация снова работает');

  const третий = поднятьСТелеграмом({ память: память });
  надо(третий.дверь.вибрацияВключена() === true, 'включённая вибрация должна пережить перезагрузку');
}

// ---------------------------------------------------------------------------
// 7. Незнакомый вид: не роняем игру, подсказываем разработчику один раз
// ---------------------------------------------------------------------------

{
  const с = поднятьСТелеграмом();
  let упало = null;
  let ответ = null;
  try {
    ответ = с.дверь.отклик('бабах');
    с.дверь.отклик('бабах');
  } catch (ошибка) {
    упало = ошибка;
  }
  надо(упало === null, 'незнакомый вид не должен ронять игру, а он бросил: ' + упало);
  надо(ответ === false, 'незнакомый вид должен вернуть «нет»');
  надо(с.отдача.просьбы.length === 0, 'незнакомый вид не должен дёргать Telegram');
  надо(с.стенд.предупреждения.length === 1,
    'о незнакомом виде говорим ровно один раз, а сказали ' + с.стенд.предупреждения.length + ' раз(а)');
}

// ---------------------------------------------------------------------------
// Итог
// ---------------------------------------------------------------------------

if (беды.length) {
  console.log('ПЛОХО, бед ' + беды.length + ':');
  for (const беда of беды) console.log('  — ' + беда);
  process.exit(1);
}
console.log('отдача под пальцем: всё хорошо — виды на месте, вне Telegram тихо, дребезга нет, выключатель помнит выбор');
process.exit(0);
