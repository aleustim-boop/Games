/* =====================================================================
   «ОТКРЫЛ ЛЕНТУ С ПУСТОЙ РУКОЙ» — прицельная проверка застрявшей партии.

   Что за беда. Человек сбросил последнюю карту. Слово при этом осталось
   у него, но решать нечем — и игра обещает нажать «Пас» сама: внизу
   появляется «Карт у вас нет — пасуем за вас…», и заводится таймер
   на секунду с небольшим. Если ровно в эту секунду открыть плашку
   «Что было», таймер срабатывал, видел открытую плашку, молча выходил
   и нового не заводил. Ходить становилось некому: обещание висело,
   партия не кончалась, победа не шла ни в серию, ни в рекорды.

   Почему обычный автоигрок этого не ловил. Он не нажимал ни строку
   подсказки, ни «Назад к столу» — то есть ленту не открывал вовсе.
   Теперь умеет (см. «автоигрок-в-браузере.js», настройка «лента»).

   Что делает эта проверка. Играет партии подряд и в каждой сторожит миг
   «пасуем за вас…»: как только он появился — открывает ленту настоящим
   нажатием по строке и держит её открытой заведомо дольше, чем длится
   пауза игры. Потом закрывает и смотрит, доигралась ли партия до итога.

   Как пользоваться (из консоли браузера, игра открыта на экране меню;
   заранее подгрузить «автоигрок-в-браузере.js», «ускоритель-пауз-в-браузере.js»
   и, если нужны числа по строке, «лента-новостей-в-браузере.js»):

       await ЛентаПустаяРука.сыграть(10);
       ЛентаПустаяРука.отчёт();

   Что считается провалом:
     — партия не дошла до итога за отведённое время (то самое зависание);
     — автоигрок записал поломку (плашка не открылась или не закрылась);
     — миг «пасуем за вас» не встретился ни разу — тогда проверка ничего
       не проверила, и об этом надо сказать прямо, а не молчать.
   ===================================================================== */

(function () {
  'use strict';

  function эл(id) { return document.getElementById(id); }
  function текст(id) { const у = эл(id); return у ? (у.textContent || '').trim() : ''; }
  function виденЭкран(id) {
    const у = эл(id);
    return Boolean(у && у.classList.contains('экран--виден'));
  }
  function ждать(мс) { return new Promise(function (д) { setTimeout(д, мс); }); }

  const партии = [];
  const провалы = [];

  async function дождатьсяИтога(потолокМс) {
    const край = Date.now() + потолокМс;
    while (Date.now() < край) {
      if (виденЭкран('экран-результата')) return true;
      await ждать(200);
    }
    return false;
  }

  /** Что игра думает о себе в этот миг — пригодится, если партия встала. */
  function внутренности() {
    try {
      const гл = function (что) { return (0, eval)(что); };
      const партия = гл('партия');
      if (!партия) return 'партии уже нет';
      return 'фаза «' + гл('фаза')(партия) + '», слово у «' + гл('ктоХодит')(партия) +
             '», карт в руке ' + партия.руки.человек.length +
             ', таймер ' + (гл('таймер') === null ? 'НЕ ЗАВЕДЁН' : 'заведён') +
             ', лента ' + (гл('лентаОткрыта') ? 'открыта' : 'закрыта') +
             ', завершена: ' + партия.завершена;
    } catch (е) { return 'заглянуть внутрь не вышло: ' + е; }
  }

  /* -------------------------------------------------------------------
     ПОДСТРОЙЩИК МИГА.

     Зачем он. Миг «Карт у вас нет — пасуем за вас…» сам по себе редок:
     нужно, чтобы человек сбросил ПОСЛЕДНЮЮ карту и слово при этом осталось
     у него. За восемь сыгранных партий он не выпал ни разу, и проверка
     тогда ничего не проверяет — а молчаливая проверка хуже отсутствующей.

     Что он делает. Дожидается ровно того положения, из которого этот миг
     и рождается в живой игре, — идёт подкидывание (или докидывание), слово
     наше, — и убирает из руки карты, будто человек их только что выложил.
     Дальше игра сама делает всё как обычно: рисует «пасуем за вас…»
     и заводит свой таймер. Никакие правила при этом не нарушаются: пустая
     рука в подкидывании — законное положение, из которого партия обязана
     идти дальше (карты доберутся из колоды в конце подхода).
     ------------------------------------------------------------------- */
  let подстройщик = null;
  let подстроеноВсего = 0;

  function пуститьПодстройщика(сколькоРаз) {
    остановитьПодстройщика();
    let осталось = сколькоРаз;
    подстройщик = setInterval(function () {
      if (осталось <= 0) return;
      try {
        const гл = function (что) { return (0, eval)(что); };
        const партия = гл('партия');
        if (!партия || партия.завершена) return;
        if (гл('этоСетеваяИгра')()) return;
        if (лентаНаЭкране()) return;
        const фаза = гл('фаза')(партия);
        if (фаза !== 'подкидывание' && фаза !== 'докидывание') return;
        if (!гл('сейчасМойХод')()) return;
        const рука = партия.руки.человек;
        if (!рука || рука.length === 0) return;
        рука.length = 0;             // «человек выложил последние карты»
        осталось--;
        подстроеноВсего++;
        гл('продолжить')();          // дальше игра решает сама
      } catch (е) { /* партия могла кончиться прямо сейчас — не беда */ }
    }, 40);
  }

  function остановитьПодстройщика() {
    if (подстройщик !== null) { clearInterval(подстройщик); подстройщик = null; }
  }

  async function однаПартия(номер, потолокМс, подстраивать) {
    if (виденЭкран('экран-результата')) эл('кнопка-ещё').click();
    else if (виденЭкран('экран-меню')) эл('кнопка-играть').click();
    await ждать(500);
    /* Ленту открываем и по случаю тоже (десятая часть шагов) — так проверяются
       и обычные её открытия посреди партии, не только прицельный миг. */
    window.Автоигрок.начать(0.6, false, { доля: 0.1, ловитьПустуюРуку: true });
    if (подстраивать) пуститьПодстройщика(подстраивать);
    const началось = Date.now();
    const дошло = await дождатьсяИтога(потолокМс);
    остановитьПодстройщика();
    const отчётИгрока = window.Автоигрок.отчёт();
    window.Автоигрок.стоп();

    const запись = {
      номер: номер,
      доиграна: дошло,
      секунд: Math.round((Date.now() - началось) / 1000),
      заголовок: дошло ? текст('текст-результата') : '',
      поймалПустуюРуку: отчётИгрока.поймалПустуюРуку,
      открытийЛенты: отчётИгрока.открытийЛенты,
      поломки: отчётИгрока.поломки
    };
    if (!дошло) {
      запись.подсказкаНаЭкране = отчётИгрока.подсказка;
      запись.внутри = внутренности();
      провалы.push('партия №' + номер + ' НЕ ДОИГРАЛАСЬ за ' + запись.секунд +
                   ' с. В строке внизу: «' + запись.подсказкаНаЭкране + '». ' + запись.внутри);
    }
    отчётИгрока.поломки.forEach(function (п) {
      провалы.push('партия №' + номер + ': ' + п.что + (п.подробности ? ' — ' + п.подробности : ''));
    });
    партии.push(запись);
    /* Если партия встала, надо вернуться в меню руками — иначе следующая
       не начнётся и весь прогон встанет вместе с ней. */
    if (!дошло && виденЭкран('экран-игры')) {
      const вМеню = эл('кнопка-в-меню');
      if (вМеню) { вМеню.click(); await ждать(400); }
      const да = эл('кнопка-выход-да');
      if (да && виденЭкран('экран-выхода')) { да.click(); await ждать(600); }
      // Плашка ленты могла остаться открытой — уводим её с дороги.
      const назад = эл('кнопка-лента-назад');
      if (назад && виденЭкран('экран-ленты')) { назад.click(); await ждать(300); }
    }
    return запись;
  }

  /* -------------------------------------------------------------------
     ПРОВЕРКА САМОЙ ПРОВЕРКИ.

     Проверка, которая никогда не краснеет, ничего не стоит. Настоящей
     старой сборки у меня нет: ленты в ней не было вовсе, поэтому и беды
     в ней нет. Значит, беду надо вернуть на живой странице — ровно ту
     самую и ровно в одну строчку: заставить «пораПасоватьСамим» отвечать
     «нет», пока плашка «Что было» открыта. Именно этим она и была.

     Ничего в файлах игры при этом не меняется: подмена живёт до
     перезагрузки страницы и снимается «починить()».
     ------------------------------------------------------------------- */
  let прежняяМерка = null;

  function лентаНаЭкране() {
    const п = эл('экран-ленты');
    return Boolean(п && п.classList.contains('экран--виден'));
  }

  /** Подменить игровую мерку «пора ли пасовать за человека» на сломанную. */
  function подменитьМерку() {
    прежняяМерка = window.пораПасоватьСамим;
    window.пораПасоватьСамим = function () {
      if (лентаНаЭкране()) return false;
      return прежняяМерка.apply(null, arguments);
    };
  }

  window.ЛентаПустаяРука = {
    сломать: function () {
      if (прежняяМерка) return 'уже сломано';
      подменитьМерку();
      return 'беда возвращена: пока лента открыта, игра не пасует за пустую руку';
    },
    починить: function () {
      if (!прежняяМерка) return 'ничего не ломали';
      window.пораПасоватьСамим = прежняяМерка;
      прежняяМерка = null;
      return 'подмена снята';
    },
    /**
     * Сыграть партии подряд.
     *   сколько     — сколько партий;
     *   потолокМс   — сколько ждать конца одной партии, прежде чем счесть её вставшей;
     *   подстраивать — сколько раз за партию подстраивать миг пустой руки
     *                  (0 — не подстраивать вовсе, играем как есть).
     */
    сыграть: async function (сколько, потолокМс, подстраивать) {
      партии.length = 0;
      провалы.length = 0;
      подстроеноВсего = 0;
      for (let н = 1; н <= (сколько || 6); н++) {
        await однаПартия(н, потолокМс || 200000, подстраивать || 0);
      }
      return this.отчёт();
    },
    отчёт: function () {
      const поймано = партии.reduce(function (с, п) { return с + п.поймалПустуюРуку; }, 0);
      const открытий = партии.reduce(function (с, п) { return с + п.открытийЛенты; }, 0);
      return {
        партий: партии.length,
        доиграно: партии.filter(function (п) { return п.доиграна; }).length,
        мигПустойРукиПойман: поймано,
        мигПодстроен: подстроеноВсего,
        всегоОткрытийЛенты: открытий,
        провалы: провалы,
        партииПодробно: партии.map(function (п) {
          return п.номер + ': ' + (п.доиграна ? 'доиграна («' + п.заголовок + '»)' : 'ВСТАЛА') +
                 ', ' + п.секунд + ' с, лент ' + п.открытийЛенты +
                 ', пустая рука поймана ' + п.поймалПустуюРуку + ' раз';
        })
      };
    }
  };
})();
