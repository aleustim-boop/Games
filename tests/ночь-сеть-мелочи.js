function узелСтраницы(с, id) { return с.документ.getElementById(id); }
function видно(с, id) { const у = узелСтраницы(с, id); return Boolean(у) && !у.classList.contains('скрыт'); }
function нажать(с, id) { const у = узелСтраницы(с, id); if (у) у.dispatchEvent('click'); return Boolean(у); }
function текст(с, id) { const у = узелСтраницы(с, id); return у ? у.textContent : ''; }

/** Войти за стол руками: «Есть код?» → код в поле → «Войти». */
async function войтиРуками(с, кодСтола) {
  нажать(с, 'кнопка-войти-по-коду');
  узелСтраницы(с, 'поле-кода').value = кодСтола;
  нажать(с, 'кнопка-войти');
  await подождать();
}

/**
 * Поддельный сервер. войти — ответ на /войти (нет — пускает с кодом «код»),
 * опрос(номер) — ответ на /что-нового (нет — молчит, человек за столом).
 */
function сервер(н) {
  const настройки = н || {};
  let опросов = 0;
  return function (путь) {
    if (путь === '/войти') {
      const кодСтола = настройки.код || 'ABCD';
      return настройки.войти ? настройки.войти() : ответСервера(200, {
        код: кодСтола, пропуск: 'пропуск-1',
        состояние: { этап: 'ожидание', код: кодСтола, версия: 1 }
      });
    }
    if (путь === '/что-нового' || путь === '/состояние') {
      опросов++;
      return настройки.опрос ? настройки.опрос(опросов) : undefined;
    }
    return undefined;
  };
}

