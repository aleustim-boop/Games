function отказДругаяИгра(данные) {
  return function () { return ответСервера(403, Object.assign({ ошибка: 'Это стол другой игры', почему: 'другая-игра' }, данные)); };
}

async function отказНаСтранице(данные, почему) {
  const с = поднятьСтраницуИгры({ сервер: сервер({ код: 'ABCD', войти: почему ? function () { return ответСервера(403, { ошибка: 'нет', почему: почему }); } : отказДругаяИгра(данные) }) });
  await войтиРуками(с, 'abcd');
  return с;
}

async function частьВтораяБ() {
  console.log('Часть 2б. Кнопка перехода в игру чужого стола');
  const ШАШКИ = { играСтола: 'шашки', названиеИгры: 'Шашки', страница: 'шашки.html' };

  const а = await отказНаСтранице(ШАШКИ);
  проверить('отказ: слова про стол игры «Шашки» на месте', /Это стол игры «Шашки»/.test(текст(а, 'сообщение-входа')), текст(а, 'сообщение-входа'));
  проверить('отказ: кнопка «Открыть «Шашки»» видна', видно(а, 'кнопка-открыть-чужую-игру') && текст(а, 'кнопка-открыть-чужую-игру') === 'Открыть «Шашки»', текст(а, 'кнопка-открыть-чужую-игру'));
  проверить('отказ: «В лобби» осталась, «Создать новый стол» не появилась', видно(а, 'кнопка-отказ-в-лобби') && !видно(а, 'кнопка-новый-стол'));
  нажать(а, 'кнопка-открыть-чужую-игру');
  проверить('нажатие ведёт на страницу шашек с кодом: шашки.html?code=ABCD', а.окно.location.href === 'шашки.html?code=ABCD', а.окно.location.href);

  // Страницу берём из реестра, а не из ответа сервера.
  const б = await отказНаСтранице({ играСтола: 'шашки', названиеИгры: 'Шашки', страница: 'левая.html' });
  нажать(б, 'кнопка-открыть-чужую-игру');
  проверить('страница игры — из реестра игр (шашки.html), а не из слов сервера', б.окно.location.href === 'шашки.html?code=ABCD', б.окно.location.href);

  // Игры нет в реестре: берём страницу сервера, только если это простое имя html.
  const в = await отказНаСтранице({ играСтола: 'неведомая', названиеИгры: 'Неведомая', страница: 'неведомая.html' });
  проверить('игры нет в реестре, страница сервера — простое имя: кнопка есть', видно(в, 'кнопка-открыть-чужую-игру'));
  нажать(в, 'кнопка-открыть-чужую-игру');
  проверить('...и ведёт на неведомая.html?code=ABCD', в.окно.location.href === 'неведомая.html?code=ABCD', в.окно.location.href);

  for (const чужой of ['https://злой.пример/e.html', '../e.html', '//злой.пример/e.html', 'javascript:alert(1).html', 'e.html?x=1']) {
    const г = await отказНаСтранице({ играСтола: 'неведомая', названиеИгры: 'Неведомая', страница: чужой });
    проверить('чужой адрес «' + чужой + '» из ответа сервера не берём: кнопки нет', !видно(г, 'кнопка-открыть-чужую-игру') && видно(г, 'кнопка-отказ-в-лобби'));
  }

  // Другие отказы кнопки перехода не показывают.
  const д = await отказНаСтранице({}, 'закрыта');
  проверить('отказ «закрыта»: кнопки «Открыть …» нет, «Создать новый стол» есть', !видно(д, 'кнопка-открыть-чужую-игру') && видно(д, 'кнопка-новый-стол'));
}

