/** Двух вещей честным узлам не хватает, а сети они нужны. */
function дополнитьУзел(у) {
  if (!('nextSibling' in у)) {
    Object.defineProperty(у, 'nextSibling', {
      get: function () {
        const р = у.parentNode;
        return р ? (р.childNodes[р.childNodes.indexOf(у) + 1] || null) : null;
      }
    });
  }
  у.insertAdjacentElement = function (где, новый) {
    const р = у.parentNode;
    р.insertBefore(новый, р.childNodes[р.childNodes.indexOf(у) + 1] || null);
    return новый;
  };
  return у;
}

