function сколькоНайдено(текстФайла, найти) {
  return текстФайла.split(найти).length - 1;
}

function ломающийРежим() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'ночь-сеть-'));
  let покраснело = 0;
  let непроверено = 0;
  const настоящая = fs.readFileSync(НАСТОЯЩАЯ_СЕТЬ, 'utf8');
  ПОЛОМКИ.forEach(function (поломка, номер) {
    const раз = сколькоНайдено(настоящая, поломка.найти);
    if (раз !== 1) {
      console.log('  ПРОВАЛ — порча «' + поломка.имя + '»: место порчи найдено ' + раз + ' раз (нужно ровно один)');
      непроверено++;
      return;
    }
    const копия = path.join(папка, 'сеть-' + номер + '.js');
    fs.writeFileSync(копия, настоящая.split(поломка.найти).join(поломка.заменить));
    const итог = spawnSync(process.execPath, [__filename, '--сеть=' + копия], { encoding: 'utf8' });
    const красных = (итог.stdout || '').split('\n').filter(function (с) { return с.indexOf('ПЛОХО') !== -1; });
    const красная = итог.status === 1 && красных.length > 0;
    if (красная) покраснело++;
    console.log((красная ? '  покраснела — ' : '  НЕ ПОКРАСНЕЛА — ') + поломка.имя + (красная ? '  (' + красных.length + ' провалов, первый: ' + красных[0].trim().slice(0, 110) + ')' : ''));
  });
  fs.rmSync(папка, { recursive: true, force: true });
  console.log('Порч: ' + ПОЛОМКИ.length + ', покраснело: ' + покраснело + (непроверено ? ', место не нашлось: ' + непроверено : ''));
  process.exit(покраснело === ПОЛОМКИ.length && !непроверено ? 0 : 3);
}

async function главное() {
  if (process.argv.indexOf('--сломать') !== -1) return ломающийРежим();
  console.log('Файл сети: ' + ФАЙЛ_СЕТИ);
  await частьПервая();
  await частьВтораяА();
  await частьВтораяБ();
  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
  process.exit(провалов > 0 || проверок < 37 ? 1 : 0);
}

главное().catch(function (беда) {
  console.log('  ПЛОХО — проверка упала: ' + (беда && беда.stack || беда));
  process.exit(1);
});
