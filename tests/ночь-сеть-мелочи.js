async function лоббиШашки(опрос, кодСтола, слова) {
  const с = поднятьСтраницуИгры({ игра: 'шашки', сервер: сервер({ код: кодСтола, опрос: function (н) { return н === 1 ? опрос() : undefined; } }) });
  await войтиРуками(с, кодСтола);
  const строка = узелСтраницы(с, 'сеть-строка-лобби');
  const лобби = узелСтраницы(с, 'экран-лобби');
  проверить('шашки, ' + слова + ': лобби на экране', лобби && лобби.classList.contains('экран--виден'));
  проверить('шашки, ' + слова + ': в лобби есть строка', Boolean(строка) && лобби.contains(строка));
  проверить('шашки, ' + слова + ': строка видна и на общей плашке «сеть-сообщение»',
    видно(с, 'сеть-строка-лобби') && строка.classList.contains('сеть-сообщение'));
  return с;
}

