/* Все тела ответов за весь прогон — под конец проверяем их разом на
   утечку номеров и полей со временем (см. пункт 11 в шапке файла). */
const собранныеТела = [];

/* ---------------------------------------------------------------------
   Подпись Telegram — по тому же правилу, что у сервера
   --------------------------------------------------------------------- */

function подписать(поля, токен) {
  const строки = Object.keys(поля)
    .filter(function (к) { return к !== 'hash'; })
    .map(function (к) { return к + '=' + поля[к]; })
    .sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(токен).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}

/** initData так, как её присылает настоящая страница Telegram. */
function подписьИгрока(номер, имя) {
  const поля = {
    query_id: 'AAF' + номер,
    user: JSON.stringify({ id: номер, first_name: имя, username: 'igrok' + номер }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  const сподписью = Object.assign({}, поля, { hash: подписать(поля, ТОКЕН_ДЛЯ_ПРОБЫ) });
  return Object.keys(сподписью)
    .map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(сподписью[к]); })
    .join('&');
}

/* ---------------------------------------------------------------------
   Разговор с дверью
   --------------------------------------------------------------------- */

/** Запрос произвольным СЫРЫМ телом (строкой) — для проверки мусорных тел. */
function сырое(путь, телоСтрокой) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(телоСтрокой, 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН_АДРЕС, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (сбой) { разобрано = null; }
        собранныеТела.push(текст);
        готово({ код: ответ.statusCode, тело: разобрано, текст: текст });
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

/** Обычный запрос с телом-объектом (в JSON превращает сама функция). */
function спросить(путь, тело) {
  return сырое(путь, JSON.stringify(тело === undefined ? {} : тело));
}

/** Подписанный запрос от имени игрока к одной из дверей присутствия. */
function дверь(путь, кто, имя, довесок) {
  const тело = Object.assign({ initData: подписьИгрока(кто, имя) }, довесок || {});
  return спросить(путь, тело);
}

/** Найти запись друга/знакомого в списке по имени. */
function найтиПоИмени(список, имя) {
  return (список || []).find(function (запись) { return запись.имя === имя; });
}

/** Короткая пауза — нужна, чтобы обойти предел «не чаще раза в 3 секунды
    на человека» у /друзья-онлайн, когда один и тот же человек стучится
    дважды по делу (не для проверки самого предела). */
function ждать(мс) {
  return new Promise(function (готово) { setTimeout(готово, мс); });
}

