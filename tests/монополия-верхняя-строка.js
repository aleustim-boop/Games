const fs = require('fs');
const os = require('os');
const path = require('path');

const ПРОЕКТ = path.join(__dirname, '..');
const ФАЙЛЫ = ['монополия.html', path.join('js', 'монополия-экран.js'), 'style-монополия-сцена.css'];

const АРГУМЕНТЫ = process.argv.slice(2);
const ЛОМАТЬ = АРГУМЕНТЫ.indexOf('--сломать') !== -1;
const АРГ_КОРЕНЬ = АРГУМЕНТЫ.find((a) => a.startsWith('--корень='));

let провалов = 0;
let проверок = 0;
function проверить(условие, слова) {
  проверок++;
  console.log((условие ? '  ок   — ' : '  ПЛОХО— ') + слова);
  if (!условие) провалов++;
  return условие;
}

/* Содержимое одного <div ...>…</div>, начиная с позиции открывающего
   тега, — учитывает вложенность div-ов внутри (шапка партии, например,
   содержит вложенный .mono-title). Вернёт null, если пара не нашлась. */
function блокDiv(html, старт) {
  const рег = /<div\b[^>]*>|<\/div>/gi;
  рег.lastIndex = старт;
  let глубина = 0;
  let найдено;
  while ((найдено = рег.exec(html)) !== null) {
    if (/^<div/i.test(найдено[0])) глубина++;
    else глубина--;
    if (глубина === 0) return html.slice(старт, рег.lastIndex);
  }
  return null;
}

/* Список блоков .mono-top в порядке появления по всему файлу. */
function найтиБлокиMonoTop(html) {
  const блоки = [];
  const метка = /<div class="mono-top">/g;
  let найдено;
  while ((найдено = метка.exec(html)) !== null) {
    const блок = блокDiv(html, найдено.index);
    if (блок) блоки.push(блок);
  }
  return блоки;
}

/* Содержимое <section id="ID" ...>…</section> целиком (учитывает
   вложенные section, если такие появятся). Вернёт null, если секции с
   таким id в файле нет вовсе. */
function блокСекции(html, idСекции) {
  const открытие = new RegExp('<section\\s+id="' + idСекции + '"[^>]*>');
  const найдено = открытие.exec(html);
  if (!найдено) return null;
  const рег = /<section\b[^>]*>|<\/section>/gi;
  рег.lastIndex = найдено.index;
  let глубина = 0;
  let м;
  while ((м = рег.exec(html)) !== null) {
    if (/^<section/i.test(м[0])) глубина++;
    else глубина--;
    if (глубина === 0) return html.slice(найдено.index, рег.lastIndex);
  }
  return null;
}

/* Проверить одну шапку .mono-top внутри секции idСекции: секция должна
   найтись, внутри нёё — ровно одна .mono-top, а в ней — [data-more] с
   правильным aria-controls и [data-back]. */
function проверитьШапку(html, idСекции, подпись) {
  const секция = блокСекции(html, idСекции);
  if (!проверить(секция !== null, 'секция #' + idСекции + ' (' + подпись + ') найдена в монополия.html')) {
    проверить(false, подпись + ': .mono-top искать негде — секции нет');
    проверить(false, подпись + ': [data-more] искать негде — секции нет');
    проверить(false, подпись + ': aria-controls искать негде — секции нет');
    проверить(false, подпись + ': [data-back] искать негде — секции нет');
    return;
  }
  const блоки = найтиБлокиMonoTop(секция);
  проверить(блоки.length === 1, 'внутри #' + idСекции + ' (' + подпись + ') ровно одна .mono-top (нашлось: ' + блоки.length + ')');
  const блок = блоки[0] || '';
  проверить(/\bdata-more\b/.test(блок), подпись + ': шапка содержит кнопку [data-more]');
  проверить(/aria-controls="лист-игры"/.test(блок), подпись + ': у кнопки [data-more] есть aria-controls="лист-игры"');
  проверить(/\bdata-back\b/.test(блок), подпись + ': шапка содержит кнопку [data-back]');
}

function проверитьКорень(корень) {
  console.log('Корень для проверки: ' + корень);

  const html = fs.readFileSync(path.join(корень, 'монополия.html'), 'utf8');
  const js = fs.readFileSync(path.join(корень, 'js', 'монополия-экран.js'), 'utf8');
  const css = fs.readFileSync(path.join(корень, 'style-монополия-сцена.css'), 'utf8');

  проверитьШапку(html, 'экран-лобби', 'лобби');
  проверитьШапку(html, 'экран-игры', 'партия');

  const всегоMonoTop = найтиБлокиMonoTop(html).length;
  console.log('  (справка) всего .mono-top в файле: ' + всегоMonoTop + ' — кнопка «⋯» по заданию есть только в двух из них');

  проверить(/id="лист-игры"/.test(html), 'в монополия.html есть узел #лист-игры');

  проверить(
    /querySelectorAll\(\s*["'`]\[data-more\]["'`]\s*\)[\s\S]{0,300}?menu\.открыть\(\)/.test(js),
    'в js/монополия-экран.js есть привязка [data-more] → menu.открыть()',
  );

  проверить(
    /html\.в-телеграме[\s\S]{0,400}?\[data-more\]/.test(css),
    'в style-монополия-сцена.css есть правило html.в-телеграме … [data-more]',
  );
}

/* Вырезать кнопку [data-more] целиком из шапки партии (#экран-игры) —
   тот же приём вырезания, что и в других ломающих сценариях проекта:
   находим ровно один такой узел, иначе кричим, что приём порчи устарел. */
function испортитьШапкуПартии(файлHtml) {
  const текст = fs.readFileSync(файлHtml, 'utf8');
  const секция = блокСекции(текст, 'экран-игры');
  if (!секция) throw new Error('приём порчи устарел: секции #экран-игры в файле нет');
  const блоки = найтиБлокиMonoTop(секция);
  if (блоки.length !== 1) {
    throw new Error('приём порчи устарел: внутри #экран-игры ожидалась ровно одна .mono-top, нашлось ' + блоки.length);
  }
  const шапка = блоки[0];
  const образецКнопки = /<button\s+data-more[\s\S]*?<\/button>/;
  const совпадение = шапка.match(образецКнопки);
  if (!совпадение) {
    throw new Error('приём порчи устарел: кнопку [data-more] в шапке партии не нашли');
  }
  const испорченнаяШапка = шапка.replace(образецКнопки, '');
  const позиция = текст.indexOf(шапка);
  const испорченныйТекст = текст.slice(0, позиция) + испорченнаяШапка + текст.slice(позиция + шапка.length);
  fs.writeFileSync(файлHtml, испорченныйТекст, 'utf8');
}

function сделатьКопиюДляЛомания() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'монополия-верхняя-строка-'));
  fs.mkdirSync(path.join(папка, 'js'), { recursive: true });
  for (const относительный of ФАЙЛЫ) {
    fs.copyFileSync(path.join(ПРОЕКТ, относительный), path.join(папка, относительный));
  }
  испортитьШапкуПартии(path.join(папка, 'монополия.html'));
  return папка;
}

if (ЛОМАТЬ) {
  const копия = сделатьКопиюДляЛомания();
  console.log('Ломающий прогон: копия испорчена в ' + копия);
  проверитьКорень(копия);
} else if (АРГ_КОРЕНЬ) {
  проверитьКорень(path.resolve(АРГ_КОРЕНЬ.slice('--корень='.length)));
} else {
  проверитьКорень(ПРОЕКТ);
}

console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
process.exit(провалов ? 1 : 0);
