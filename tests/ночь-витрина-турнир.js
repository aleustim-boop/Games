function заменитьРовноОдинРаз(текст, было, стало, имя) {
  const число = текст.split(было).length - 1;
  if (число !== 1) throw new Error('порча «' + имя + '»: нашлось мест ' + число + ' вместо одного — ноль найденного это провал');
  return текст.replace(было, function () { return стало; });
}

/** Каждая порча делается во временной папке; проверка на копии обязана краснеть. */
function сломать(папка) {
  fs.mkdirSync(папка, { recursive: true });
  const исходники = {
    // Переводы строк приводим к одному виду, чтобы многострочные куски находились и в CRLF-файле.
    game: fs.readFileSync(path.join(КОРЕНЬ, 'js', 'game.js'), 'utf8').replace(/\r\n/g, '\n'),
    telegram: fs.readFileSync(path.join(КОРЕНЬ, 'js', 'telegram.js'), 'utf8').replace(/\r\n/g, '\n')
  };
  let непокраснело = 0;
  ПОРЧИ.forEach(function (порча, i) {
    const дир = path.join(папка, 'порча-' + (i + 1));
    fs.mkdirSync(дир, { recursive: true });
    const копии = {
      game: path.join(дир, 'game.js'),
      telegram: path.join(дир, 'telegram.js')
    };
    fs.writeFileSync(копии.game, исходники.game);
    fs.writeFileSync(копии.telegram, исходники.telegram);
    let текст = заменитьРовноОдинРаз(исходники[порча.файл], порча.было, порча.стало, порча.имя);
    if (порча.ещё) текст = заменитьРовноОдинРаз(текст, порча.ещё.было, порча.ещё.стало, порча.имя);
    fs.writeFileSync(копии[порча.файл], текст);
    const итог = spawnSync(process.execPath,
      [__filename, '--game', копии.game, '--telegram', копии.telegram], { encoding: 'utf8' });
    const краснеет = итог.status === 1;
    console.log((краснеет ? 'покраснела  ' : 'НЕ ПОКРАСНЕЛА  ') + порча.файл + ': ' + порча.имя);
    if (!краснеет) непокраснело++;
  });
  console.log('\nПорч: ' + ПОРЧИ.length + ', не покраснело: ' + непокраснело);
  process.exit(непокраснело === 0 ? 0 : 3);
}

