/** Любой id находится (пустышка), как в tests/турнир-вход.js. */
function позволитьЛюбыеId(документ) {
  const оригинал = документ.getElementById;
  const пустышки = new Map();
  документ.getElementById = function (id) {
    const найден = оригинал(id);
    if (найден) return найден;
    if (пустышки.has(id)) return пустышки.get(id);
    const узел = документ.createElement('div');
    узел.id = id;
    пустышки.set(id, узел);
    return узел;
  };
}

/** game.js в песочнице с поддельными часами и таймерами, которые дёргаем рукой. */
function поднятьИгру(часы) {
  const документ = сделатьДокумент();
  позволитьЛюбыеId(документ);
  const таймеры = [];
  const окно = {
    document: документ,
    addEventListener: function () {}, removeEventListener: function () {},
    matchMedia: function () { return { matches: false, addEventListener: function () {}, addListener: function () {} }; },
    localStorage: { getItem: function () { return null; }, setItem: function () {}, removeItem: function () {} },
    innerWidth: 390, innerHeight: 844,
    requestAnimationFrame: function (ф) { return setTimeout(ф, 0); },
    cancelAnimationFrame: function (id) { clearTimeout(id); },
    getComputedStyle: function () { return { fontSize: '16px', lineHeight: '19.2px', getPropertyValue: function () { return ''; } }; },
    ЛистЕщё: {
      подключить: function () {
        return {
          открыть: function () {}, закрыть: function () {}, открыт: function () { return false; },
          освежитьКнопкуНастроек: function () {}, спроситьЗавершить: function () { return false; }
        };
      }
    },
    ТурнирЭкран: { открыть: function () {} },
    вопросовПроТурнир: 0
  };
  const песочница = {
    window: окно, document: документ, localStorage: окно.localStorage,
    navigator: { userAgent: 'тест ночь-витрина' },
    console: { log: function () {}, info: function () {}, warn: function () {}, error: function () {} },
    Date: часы.Дата,
    setTimeout: setTimeout, clearTimeout: clearTimeout,
    setInterval: function (ф, мс) { const т = { ф: ф, мс: мс, снят: false }; таймеры.push(т); return т; },
    clearInterval: function (т) { if (т) т.снят = true; },
    requestAnimationFrame: окно.requestAnimationFrame, cancelAnimationFrame: окно.cancelAnimationFrame,
    getComputedStyle: окно.getComputedStyle
  };
  песочница.globalThis = песочница;
  vm.createContext(песочница);
  vm.runInContext(fs.readFileSync(ПУТЬ_GAME, 'utf8'), песочница, { filename: ПУТЬ_GAME + ' (ночь-витрина)' });
  return {
    окно, документ, таймеры,
    спросить: function (выражение) { return vm.runInContext(выражение, песочница); },
    живыеТаймеры: function () { return таймеры.filter(function (т) { return !т.снят; }); },
    /** Один «тик» всех живых таймеров. */
    тикнуть: function () { таймеры.filter(function (т) { return !т.снят; }).forEach(function (т) { т.ф(); }); }
  };
}

async function проверитьВитрину() {
  console.log('\nА. Пометка плитки по часам');
  const начало = Date.UTC(2026, 9, 3, 17, 0, 0);          // 20:00 МСК
  const конец = начало + 30 * 60000;
  const часы = поддельныеЧасы(начало - 60000);            // 19:59:00 МСК
  const игра = поднятьИгру(часы);
  const экран = игра.документ.узел('div', { id: 'экран-витрины', класс: 'экран экран--виден' });
  игра.документ.body.appendChild(экран);
  игра.документ.getElementById('кнопка-вернуться-в-игру').classList.add('скрыт');
  const пометка = () => игра.документ.getElementById('пометка-дурак').textContent;

  игра.спросить('window.Сеть = { турнир: function () { window.вопросовПроТурнир++; ' +
    'return Promise.resolve({ ок: true, вид: { состояние: "запись", началоМс: ' + начало + ', конецМс: ' + конец + ' } }); } }; ' +
    'последнийВопросПроТурнирМс = 0;');
  игра.спросить('освежитьВитрину()');
  await пауза(20);
  надо(пометка() === 'турнир в 20:00', 'А1) в 19:59 на плитке «турнир в 20:00»', 'получено: «' + пометка() + '»');
  надо(игра.окно.вопросовПроТурнир === 1, 'А2) вопрос серверу один', 'вопросов: ' + игра.окно.вопросовПроТурнир);
  надо(игра.живыеТаймеры().length >= 1, 'А3) пока витрина видна, часы пометки заведены',
    'живых таймеров: ' + игра.живыеТаймеры().length);
  надо(игра.живыеТаймеры().every((т) => т.мс === 30000), 'А4) таймер тикает раз в 30 секунд',
    'периоды: ' + игра.живыеТаймеры().map((т) => т.мс).join(','));

  часы.установить(начало - 30000);                         // 19:59:30
  игра.тикнуть();
  надо(пометка() === 'турнир в 20:00', 'А5) в 19:59:30 пометка ещё прежняя', 'получено: «' + пометка() + '»');

  часы.установить(начало + 30000);                         // 20:00:30
  игра.тикнуть();
  надо(пометка() === 'турнир идёт', 'А6) к 20:00:30 пометка сменилась на «турнир идёт»', 'получено: «' + пометка() + '»');
  надо(игра.окно.вопросовПроТурнир === 1, 'А7) сменилась без нового запроса к серверу', 'вопросов: ' + игра.окно.вопросовПроТурнир);

  часы.установить(конец + 30000);                          // 20:30:30
  игра.тикнуть();
  надо(пометка() === '', 'А8) после конца пар пометки нет', 'получено: «' + пометка() + '»');
  надо(игра.окно.вопросовПроТурнир === 1, 'А9) и снова без запроса к серверу', 'вопросов: ' + игра.окно.вопросовПроТурнир);

  экран.classList.remove('экран--виден');                  // витрина ушла с экрана
  игра.тикнуть();
  надо(игра.живыеТаймеры().length === 0, 'А10) витрина не видна — таймер снят',
    'живых таймеров: ' + игра.живыеТаймеры().length);

  /* А11. Возврат на витрину: пометка свежая сразу, не через 30 с. */
  игра.спросить('пометкаТурнира = "турнир в 20:00"; последнийВидТурнира = { состояние: "запись", началоМс: ' +
    начало + ', конецМс: ' + конец + ' }; последнийВопросПроТурнирМс = Date.now();');
  часы.установить(начало + 30000);
  экран.classList.add('экран--виден');
  игра.спросить('освежитьВитрину()');
  надо(пометка() === 'турнир идёт', 'А11) при возврате на витрину пометка пересчитана сразу, без ожидания таймера',
    'получено: «' + пометка() + '»');
}

/* ---------------------------------------------------------------------
   Б) «перед-закрытием»: ошибка подписчика не выходит наружу
   --------------------------------------------------------------------- */

async function проверитьЗакрытие() {
  console.log('\nБ. Ошибка подписчика «перед-закрытием»');
  const тройка = { close: 0, дошлоДоOnerror: [], дошлоДоСлушателяError: [], предупреждения: [], порядок: [] };
  const м = поднятьTelegramJS({
    исходник: fs.readFileSync(ПУТЬ_TELEGRAM, 'utf8'),
    telegram: { close: function () { тройка.close++; тройка.порядок.push('close'); } },
    собиратьПредупреждения: true
  });
  надо(!!м.окно.Телеграм && typeof м.окно.Телеграм.свернуть === 'function', 'Б0) telegram.js поднялся, дверь «свернуть» на месте');
  if (!м.окно.Телеграм) return;

  /* Окно ведёт себя как браузер: dispatchEvent зовёт подписчиков, ошибка
     подписчика не рвёт рассылку, а «сообщается» — сперва слушателям error
     с capture, потом window.onerror и обычным слушателям error. */
  const слушатели = {};
  м.окно.addEventListener = function (имя, ф, захват) { (слушатели[имя] = слушатели[имя] || []).push({ ф: ф, захват: !!захват }); };
  м.окно.removeEventListener = function (имя, ф, захват) {
    слушатели[имя] = (слушатели[имя] || []).filter(function (л) { return !(л.ф === ф && л.захват === !!захват); });
  };
  м.окно.onerror = function (сообщение) { тройка.дошлоДоOnerror.push(String(сообщение)); return false; };
  const прежний = м.окно.onerror;
  function сообщитьОбОшибке(ошибка) {
    let остановлено = false;
    const событие = {
      type: 'error', message: ошибка.message, error: ошибка,
      stopImmediatePropagation: function () { остановлено = true; },
      preventDefault: function () {}
    };
    (слушатели.error || []).filter((л) => л.захват).forEach((л) => { if (!остановлено) л.ф(событие); });
    if (остановлено) return;
    if (typeof м.окно.onerror === 'function') м.окно.onerror(ошибка.message, '', 0, 0, ошибка);
    (слушатели.error || []).filter((л) => !л.захват).forEach((л) => тройка.дошлоДоСлушателяError.push(ошибка.message));
  }
  м.окно.dispatchEvent = function (событие) {
    (слушатели[событие.type] || []).slice().forEach(function (л) {
      try { л.ф(событие); } catch (ошибка) { сообщитьОбОшибке(ошибка); }
    });
    return true;
  };
  м.песочница.CustomEvent = class { constructor(тип) { this.type = тип; } };

  let второйЗвали = 0;
  м.окно.addEventListener('перед-закрытием', function () { throw new Error('подписчик упал'); });
  м.окно.addEventListener('перед-закрытием', function () { второйЗвали++; });

  м.окно.Телеграм.свернуть();
  await пауза(30);

  надо(тройка.close === 1, 'Б1) close зовётся, хотя подписчик бросил ошибку', 'вызовов close: ' + тройка.close);
  надо(второйЗвали === 1, 'Б2) следующий подписчик всё равно получил событие', 'раз: ' + второйЗвали);
  надо(тройка.дошлоДоOnerror.length === 0, 'Б3) ошибка подписчика не дошла до window.onerror',
    'дошло: ' + тройка.дошлоДоOnerror.join('; '));
  надо(тройка.дошлоДоСлушателяError.length === 0, 'Б4) и до слушателей события «error»',
    'дошло: ' + тройка.дошлоДоСлушателяError.join('; '));
  надо(м.предупреждения.some((с) => с.indexOf('подписчик упал') !== -1), 'Б5) ошибка записана в console.warn',
    'предупреждения: ' + JSON.stringify(м.предупреждения));
  надо(м.окно.onerror === прежний, 'Б6) прежний window.onerror возвращён на место');
  надо((слушатели.error || []).length === 0, 'Б7) временный слушатель «error» снят', 'осталось: ' + (слушатели.error || []).length);
}

