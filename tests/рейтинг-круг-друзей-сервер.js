async function сценарийБезДрузей(порт) {
  console.log('\n1. Игрок вообще без друзей: естьДрузья должно быть false');
  const ответ = await рейтингИгрока(порт, БЕЗ_ДРУЗЕЙ, 'БезДрузей');

  проверить(ответ.номер === 200, 'дверь /рейтинг ответила кодом 200 (было: ' + ответ.номер + ')');
  проверить(ответ.данные && ответ.данные.ок === true && ответ.данные.узналиВас === true,
    'сервер опознал подпись и вернул рейтинг');
  проверить(Boolean(ответ.данные && ответ.данные.друзья), 'поле «друзья» присутствует в ответе');
  if (ответ.данные && ответ.данные.друзья) {
    проверить(ответ.данные.друзья.естьДрузья === false,
      'у игрока без единого друга естьДрузья = false (было: ' + ответ.данные.друзья.естьДрузья + ')');
    проверить(ответ.данные.друзья.всего === 0,
      'у игрока без друзей срез друзей пуст: всего = 0 (было: ' + ответ.данные.друзья.всего + ')');
  }
  /* Остальной ответ (общий срез, поПравилу, поСоставу) не должен
     сломаться из-за пустого списка друзей — рейтинг «Все игроки»
     обязан рисоваться как раньше. */
  проверить(ответ.данные && typeof ответ.данные.всего === 'number',
    'общий срез рейтинга по-прежнему на месте (поле «всего» — число)');
}

async function сценарийСДрузьями(порт) {
  console.log('\n2. Игрок с друзьями, у которых есть очки: срез верный, номер и посторонний не утекают');
  const ответ = await рейтингИгрока(порт, МЕНЯ, 'Меня');

  проверить(ответ.номер === 200, 'дверь /рейтинг ответила кодом 200 (было: ' + ответ.номер + ')');
  проверить(Boolean(ответ.данные && ответ.данные.друзья), 'поле «друзья» присутствует в ответе');
  const срез = ответ.данные && ответ.данные.друзья;
  if (!срез) return;

  проверить(срез.естьДрузья === true, 'у МЕНЯ друзья есть: естьДрузья = true (было: ' + срез.естьДрузья + ')');
  /* Участников: я + ДРУГ_А + ДРУГ_Б = 3 (ДРУГ_БЕЗ_ИГР без записи в
     таблице не считается — см. сценарий 3). */
  проверить(срез.всего === 3, 'в срезе друзей 3 участника (я + два играющих друга), было: ' + срез.всего);
  проверить(срез.яВТаблице === true, 'МЕНЯ в таблице друзей яВТаблице = true');

  проверить(Array.isArray(срез.верхушка), 'верхушка — массив');
  if (Array.isArray(срез.верхушка)) {
    const имена = срез.верхушка.map(function (стр) { return стр.имя; });
    проверить(имена.indexOf('ДругА') !== -1, 'ДругА виден в верхушке (было: ' + имена.join(', ') + ')');
    проверить(имена.indexOf('ДругБ') !== -1, 'ДругБ виден в верхушке (было: ' + имена.join(', ') + ')');
    const местоА = имена.indexOf('ДругА');
    const местоБ = имена.indexOf('ДругБ');
    if (местоА !== -1 && местоБ !== -1) {
      проверить(местоА < местоБ, 'ДругА (больше очков) стоит выше ДругБ в верхушке');
    }
  }

  /* ГЛАВНАЯ ПРОВЕРКА: номер Telegram друга и посторонний не встречаются
     нигде во всём ответе двери — не только в поле «друзья», а во всём
     JSON целиком (общий срез, поПравилу, поСоставу — тоже отдаём тому
     же игроку тем же ответом). */
  проверить(!номерВстречаетсяВТексте(ответ.текст, ДРУГ_А),
    'номер друга ДРУГ_А (' + ДРУГ_А + ') нигде не встречается в ответе /рейтинг');
  проверить(!номерВстречаетсяВТексте(ответ.текст, ДРУГ_Б),
    'номер друга ДРУГ_Б (' + ДРУГ_Б + ') нигде не встречается в ответе /рейтинг');
  проверить(ответ.текст.indexOf('"номер"') === -1,
    'в ответе вообще нет ключа "номер" (сервер не должен отдавать сырые номера)');

  /* Посторонний — не друг, но у него тоже есть очки в общей таблице
     этой игры (см. засеятьРейтинг), поэтому он ЗАКОННО может всплыть
     в общем срезе рейтинга («Все игроки», поПравилу, поСоставу) — это
     не утечка, а нормальная работа общего рейтинга. Утечкой было бы
     появление его имени именно ВНУТРИ среза «друзья» — сверяем только
     этот кусок ответа, отдельно от остального JSON. */
  const текстСрезаДрузей = JSON.stringify(срез);
  проверить(текстСрезаДрузей.indexOf('Посторонний') === -1,
    'имени "Посторонний" нет внутри среза «друзья» (посторонний не друг), было: ' + текстСрезаДрузей);
  проверить(!номерВстречаетсяВТексте(текстСрезаДрузей, ПОСТОРОННИЙ),
    'номер ПОСТОРОННЕГО (' + ПОСТОРОННИЙ + ') не встречается внутри среза «друзья»');
  /* А вот номер Telegram — не должен всплывать НИГДЕ во всём ответе,
     включая общий срез: сервер вообще никогда не отдаёт сырые номера. */
  проверить(!номерВстречаетсяВТексте(ответ.текст, ПОСТОРОННИЙ),
    'номер ПОСТОРОННЕГО (' + ПОСТОРОННИЙ + ') нигде не встречается в целом ответе /рейтинг');
}

async function сценарийДругБезЗаписи(порт) {
  console.log('\n3. Друг без единой партии в этой игре — не теряется молча, а честно пропущен');
  const ответ = await рейтингИгрока(порт, МЕНЯ, 'Меня');
  const срез = ответ.данные && ответ.данные.друзья;
  проверить(Boolean(срез), 'поле «друзья» на месте и в этом сценарии');
  if (!срез) return;

  /* Контракт срезПоСписку (см. server/рейтинг.js, записиПоСписку):
     друг без записи в таблице просто не входит в список участников —
     ни в «всего», ни в верхушке, ни в вокругМеня, но и ничего не роняет. */
  проверить(ответ.текст.indexOf('ДругБезИгр') === -1,
    'имени друга без единой партии нет в ответе (он честно пропущен, не выдуман задним числом)');
  проверить(!номерВстречаетсяВТексте(ответ.текст, ДРУГ_БЕЗ_ИГР),
    'номер друга без партий тоже нигде не всплывает');
  /* «всего» = 3 (я + два играющих друга) — ДРУГ_БЕЗ_ИГР в счёт не идёт,
     это тот же расчёт, что и в сценарии 2, но проговорённый отдельно,
     чтобы падение здесь читалось как «друг без записи что-то испортил». */
  проверить(срез.всего === 3,
    'друг без записи не увеличивает и не уменьшает «всего» (было: ' + срез.всего + ', ожидали 3)');
}

