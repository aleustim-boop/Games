function запрос(порт, путь, тело) {
  return new Promise(function (готово) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const req = http.request({
      host: ХОСТ, port: порт, method: 'POST', path: encodeURI(путь),
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let куски = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (к) { куски += к; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(куски); } catch (е) { разобрано = { разбор: 'не JSON', сырое: куски }; }
        готово({ номер: ответ.statusCode, данные: разобрано, текст: куски });
      });
    });
    req.on('error', function (е) { готово({ номер: 0, данные: { ошибка: String(е.message) } }); });
    req.write(данные);
    req.end();
  });
}

function подписать(поля, токен) {
  const строки = Object.keys(поля)
    .filter(function (к) { return к !== 'hash'; })
    .map(function (к) { return к + '=' + поля[к]; })
    .sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(токен).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}

function initDataДля(номер, имя) {
  const поля = {
    query_id: 'AAKRUG' + номер,
    user: JSON.stringify({ id: номер, first_name: имя, username: 'игрок' + номер }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  const сподписью = Object.assign({}, поля, { hash: подписать(поля, ТОКЕН_ДЛЯ_ПРОБЫ) });
  return Object.keys(сподписью)
    .map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(сподписью[к]); })
    .join('&');
}

function рейтингИгрока(порт, номер, имя) {
  return запрос(порт, '/рейтинг', { initData: initDataДля(номер, имя), игра: ИГРА });
}

