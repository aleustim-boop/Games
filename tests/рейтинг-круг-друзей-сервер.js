/* Ищем точное число как отдельный номер, не как хвост другого числа —
   цифры это ASCII, \b на них работает исправно (в отличие от кириллицы). */
function номерВстречаетсяВТексте(текст, номер) {
  const рег = new RegExp('\\b' + String(номер) + '\\b');
  return рег.test(текст);
}

