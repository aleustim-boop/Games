(async function () {
  console.log('=== Рейтинг: круг «Друзья» через настоящую дверь /рейтинг ===');

  сервера.оснасткаДляПроверки(ТОКЕН_ДЛЯ_ПРОБЫ, function () { return { ok: true }; });
  const сервер = сервера.создатьСервер();
  await new Promise(function (готово, беда) {
    сервер.once('error', беда);
    сервер.listen(ПОРТ, ХОСТ, готово);
  });
  const порт = сервер.address().port;
  console.log('Тестовый сервер комнат поднят на порту ' + порт +
    ' (require в этом процессе, боевой 8790 не трогаем), данные в ' + СВОЯ_ПАПКА);

  let сбой = null;
  try {
    засеятьРейтинг();
    засеятьДружбу();
    await сценарийБезДрузей(порт);
    await сценарийСДрузьями(порт);
    await сценарийДругБезЗаписи(порт);
  } catch (беда) {
    сбой = беда;
  } finally {
    await new Promise(function (готово) { сервер.close(готово); });
    сервера.оснасткаДляПроверки();
    try { fs.rmSync(СВОЯ_ПАПКА, { recursive: true, force: true }); } catch (е) { /* временная папка, не страшно */ }
  }

  console.log('\n----------------------------------------');
  if (сбой) {
    console.log('ПРОВЕРКА ОБОРВАЛАСЬ: ' + сбой.message);
    console.log(сбой.stack);
  }
  for (const беда of провалы) console.log('  - ' + беда);
  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалы.length);
  process.exit(сбой || провалы.length > 0 ? 1 : 0);
})();
