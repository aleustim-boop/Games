/* =====================================================================
   ЗАМЕР СЕРИИ ПОБЕД В БРАУЗЕРЕ — «а что человек увидит в рамке итога?»

   Зачем. Счёт побед живёт не в правилах, а на экране: заголовок партии,
   строчка под ним («Побед подряд: 3»), звук и запись в рекордах. Проверить
   это в Node нельзя — там нет экрана. А руками нужны десятки партий подряд,
   иначе обрыв серии не поймать.

   Что делает. Играет партии подряд НАСТОЯЩИМИ нажатиями (руками работает
   автоигрок из «автоигрок-в-браузере.js») и после каждой записывает:
     — заголовок итога («Вы выиграли!» / «Вы проиграли» / «Ничья»);
     — строчку про серию под ним;
     — что игра сохранила в памяти (серия и лучший рекорд);
     — какой звук прозвучал (мы подслушиваем звуковые вызовы игры).
   Потом сам сверяет: победа обязана растить серию на единицу, поражение —
   обнулять её, ничья — не менять.

   Как пользоваться (из консоли браузера, игра открыта на экране меню):
       // сначала подгрузить автоигрока и этот файл
       await ЗамерСерии.сыграть(8);      // 8 партий подряд
       ЗамерСерии.отчёт();               // таблица партий и найденные расхождения

   Ничего в игре не меняет: только нажимает кнопки и читает надписи.
   ===================================================================== */

(function () {
  'use strict';

  function эл(id) { return document.getElementById(id); }
  function текст(id) { const у = эл(id); return у ? (у.textContent || '').trim() : ''; }
  function виденЭкран(id) {
    const у = эл(id);
    return Boolean(у && у.classList.contains('экран--виден'));
  }
  function ждать(мс) { return new Promise(function (д) { setTimeout(д, мс); }); }

  /* Подслушиваем звук. Игра зовёт звукПобеды/звукПроигрыша, но наружу их
     не отдаёт, поэтому слушаем звуковой движок браузера и записываем ЧАСТОТЫ.
     Победа в игре звучит двумя нотами 523 и 784 герца, проигрыш — 300 и 160
     (js/game.js, «звукПобеды» и «звукПроигрыша»). По этим числам и узнаём,
     какой именно звук прозвучал, а не просто «какой-то звук был». */
  const звуки = { частоты: [], подключено: false };
  const ПОБЕДА_ГЦ = [523, 784];
  const ПРОИГРЫШ_ГЦ = [300, 160];
  function слушатьЗвук() {
    if (звуки.подключено) return;
    const АК = window.AudioContext || window.webkitAudioContext;
    if (!АК || !АК.prototype.createOscillator) return;
    const прежний = АК.prototype.createOscillator;
    АК.prototype.createOscillator = function () {
      const узел = прежний.apply(this, arguments);
      try {
        const частота = узел.frequency;
        const прежнееЗначение = частота.setValueAtTime.bind(частота);
        частота.setValueAtTime = function (гц) {
          звуки.частоты.push(Math.round(гц));
          return прежнееЗначение.apply(null, arguments);
        };
      } catch (е) { /* не вышло подслушать — не беда */ }
      return узел;
    };
    звуки.подключено = true;
  }
  function прозвучало(частоты, ноты) {
    return ноты.every(function (гц) { return частоты.indexOf(гц) !== -1; });
  }

  function изПамяти() {
    let рекорды = null;
    try { рекорды = JSON.parse(localStorage.getItem('подкидной-дурак:рекорды') || 'null'); }
    catch (е) { рекорды = 'память испорчена: ' + е; }
    return {
      серия: localStorage.getItem('подкидной-дурак:серия'),
      лучший: рекорды && рекорды.лучший,
      строк: рекорды && рекорды.таблица ? рекорды.таблица.length : 0,
      последняя: рекорды && рекорды.последняяСерия ? рекорды.последняяСерия : null
    };
  }

  /** Какой это исход по заголовку — так его читает живой человек. */
  function исходПоЗаголовку(заголовок) {
    if (/выиграл/i.test(заголовок)) return 'победа';
    if (/проиграл/i.test(заголовок)) return 'поражение';
    if (/ничья/i.test(заголовок)) return 'ничья';
    return 'непонятно';
  }

  /** Число из строчки «Побед подряд: N» или «было N побед подряд». */
  function числоИзРамки(рамка) {
    const м = рамка.match(/(\d+)/);
    return м ? Number(м[1]) : null;
  }

  const партии = [];
  const расхождения = [];

  async function дождатьсяИтога(потолокМс) {
    const край = Date.now() + потолокМс;
    while (Date.now() < край) {
      if (виденЭкран('экран-результата')) return true;
      await ждать(200);
    }
    return false;
  }

  /** Одна партия целиком: нажать «Играть», доиграть, прочитать итог. */
  async function однаПартия(номер, ожидаемаяСерияДо) {
    if (виденЭкран('экран-результата')) эл('кнопка-ещё').click();
    else if (виденЭкран('экран-меню')) эл('кнопка-играть').click();
    await ждать(500);
    /* Идёт ли партия по сети — спрашиваем саму игру, а не гадаем по экрану.
       Сначала я смотрел на строку «Друг на связи», и это оказалось неверно:
       за сетевым столом компанией эта строка спрятана, и замер счёл партию
       обычной игрой с ботом. Признак «как на экране» врёт — берём готовый
       ответ у игры. */
    const поСети = Boolean(window.ИграПоСети && window.ИграПоСети.идёт && window.ИграПоСети.идёт());
    window.Автоигрок.начать(0.6, false);
    звуки.частоты.length = 0;   // слушаем только те ноты, что прозвучат в этой партии
    const дошло = await дождатьсяИтога(240000);
    window.Автоигрок.стоп();
    if (!дошло) {
      расхождения.push('партия №' + номер + ': до конца не доиграла за 4 минуты. ' +
                       'Подсказка на экране: «' + (window.Автоигрок.отчёт().подсказка) + '»');
      return null;
    }
    await ждать(1200);   // рамка итога дописывается после сохранения рекорда

    const запись = {
      номер: номер,
      заголовок: текст('текст-результата'),
      пояснение: текст('пояснение-результата'),
      рамка: текст('серия-итога'),
      звукПобеды: прозвучало(звуки.частоты, ПОБЕДА_ГЦ),
      звукПроигрыша: прозвучало(звуки.частоты, ПРОИГРЫШ_ГЦ),
      память: изПамяти(),
      поломкиАвтоигрока: window.Автоигрок.отчёт().поломки
    };
    запись.исход = исходПоЗаголовку(запись.заголовок);
    запись.поСети = поСети;

    const серияПосле = Number(запись.память.серия);

    /* Партия с живым другом в серию и рекорды не идёт вовсе — так задумано:
       серия побед считается только против бота (см. «подвестиСетевойИтог»
       в js/game.js). Поэтому здесь у нас другое требование: серия обязана
       остаться ровно такой, какой была, чем бы партия ни кончилась. */
    if (поСети) {
      if (серияПосле !== ожидаемаяСерияДо) {
        расхождения.push('партия №' + номер + ' (по сети): серия была ' + ожидаемаяСерияДо +
                         ', а стала ' + серияПосле +
                         ' — победы над живым другом не должны попадать в серию');
      }
      if (запись.исход === 'победа' && !запись.звукПобеды) {
        расхождения.push('партия №' + номер + ' (по сети): «' + запись.заголовок +
                         '», а звук победы не прозвучал');
      }
      if (запись.исход === 'поражение' && !запись.звукПроигрыша) {
        расхождения.push('партия №' + номер + ' (по сети): «' + запись.заголовок +
                         '», а звук проигрыша не прозвучал');
      }
      партии.push(запись);
      return серияПосле;
    }

    // Дальше — обычная игра с ботом: сверяем заголовок и то, что вышло в серии.
    const надо = запись.исход === 'победа' ? ожидаемаяСерияДо + 1
               : запись.исход === 'поражение' ? 0
               : ожидаемаяСерияДо;
    if (запись.исход === 'непонятно') {
      расхождения.push('партия №' + номер + ': заголовок непонятный — «' + запись.заголовок + '»');
    } else if (серияПосле !== надо) {
      расхождения.push('партия №' + номер + ': на экране «' + запись.заголовок +
                       '», серия до партии была ' + ожидаемаяСерияДо +
                       ', должна стать ' + надо + ', а стала ' + серияПосле +
                       ' (в рамке написано: «' + запись.рамка + '»)');
    }
    // Рамка должна говорить то же самое, что и память.
    const вРамке = числоИзРамки(запись.рамка);
    if (запись.исход === 'победа' && вРамке !== серияПосле) {
      расхождения.push('партия №' + номер + ': в памяти серия ' + серияПосле +
                       ', а в рамке итога написано «' + запись.рамка + '»');
    }
    if (запись.исход === 'победа' && !запись.звукПобеды) {
      расхождения.push('партия №' + номер + ': на экране «' + запись.заголовок +
                       '», а звук победы (523 и 784 Гц) не прозвучал');
    }
    if (запись.исход === 'поражение' && !запись.звукПроигрыша) {
      расхождения.push('партия №' + номер + ': на экране «' + запись.заголовок +
                       '», а звук проигрыша (300 и 160 Гц) не прозвучал');
    }
    if (запись.исход === 'поражение' && ожидаемаяСерияДо > 0 &&
        !/прервана/i.test(запись.рамка)) {
      расхождения.push('партия №' + номер + ': проигрыш при серии ' + ожидаемаяСерияДо +
                       ', а про обрыв серии не сказано ни слова: «' + запись.рамка + '»');
    }
    партии.push(запись);
    return серияПосле;
  }

  window.ЗамерСерии = {
    сыграть: async function (сколько) {
      слушатьЗвук();
      let серия = Number(localStorage.getItem('подкидной-дурак:серия') || 0);
      for (let i = 1; i <= сколько; i++) {
        const после = await однаПартия(партии.length + 1, серия);
        if (после === null) break;
        серия = после;
      }
      return 'сыграно партий: ' + партии.length;
    },
    отчёт: function () {
      return {
        партий: партии.length,
        строки: партии.map(function (п) {
          return '№' + п.номер + (п.поСети ? ' (по сети)' : '') + ' ' + п.исход +
                 ' | «' + п.заголовок + '» | «' + п.пояснение +
                 '» | «' + п.рамка +
                 '» | серия в памяти: ' + п.память.серия + ', лучший: ' + п.память.лучший +
                 ', строк в таблице: ' + п.память.строк +
                 ', звук победы: ' + (п.звукПобеды ? 'был' : 'нет') +
                 ', звук проигрыша: ' + (п.звукПроигрыша ? 'был' : 'нет');
        }),
        расхождения: расхождения,
        поломкиАвтоигрока: партии.reduce(function (с, п) { return с.concat(п.поломкиАвтоигрока); }, [])
      };
    },
    сброс: function () { партии.length = 0; расхождения.length = 0; return 'очищено'; }
  };
})();
