'use strict';

/* =====================================================================
   РЕЙТИНГ: срез «только друзья» (срезПоСписку / записиПоСписку).

   Что проверяем. server/рейтинг.js получил две новые функции для
   будущего фильтра «Друзья» на экране рейтинга:
     - срезПоСписку(игра, номер, списокНомеров) — наружная, отдаёт
       ту же форму ответа, что общий срез: {всего, яВТаблице, я,
       верхушка, вокругМеня};
     - записиПоСписку(игра, номер, списокНомеров) — внутренняя, строит
       список участников: сам игрок + те из списка друзей, у кого есть
       запись в таблице этой игры (без дублей, без утечки постороннего).

   HTTP-маршрута для этого среза ещё нет (следующий этап), поэтому
   проверка идёт напрямую через require('../server/рейтинг.js') —
   без http-сервера, как договорились со штабом. Данные уводим во
   временную папку, чтобы не тронуть боевой файл рейтинга.

   Что значит «ломающий запуск». Флаг --сломать подменяет
   рейтинг.срезПоСписку на рейтинг.срезДляИгрока — это ровно та
   ошибка, которую легко допустить в реальности: забыть учесть список
   друзей и вернуть срез по ВСЕЙ таблице игры. Посторонний, который
   не входит в список друзей, тут же появляется в ответе, и часть
   проверок обязана покраснеть.

   Запуск:
       node tests/рейтинг-срез-по-друзьям.js

   Ломающий запуск (обязан покраснеть):
       node tests/рейтинг-срез-по-друзьям.js --сломать

   Выход 0 — провалов нет, 1 — есть.
   ===================================================================== */

const path = require('path');
const os = require('os');
const fs = require('fs');

/* Уводим данные в сторону ДО подключения сервера/рейтинга, чтобы не
   тронуть боевые данные владельца. */
const СВОЯ_ПАПКА = path.join(os.tmpdir(), 'рейтинг-срез-по-друзьям-тест-' + process.pid);
if (!fs.existsSync(СВОЯ_ПАПКА)) fs.mkdirSync(СВОЯ_ПАПКА, { recursive: true });
process.env.GAMES_DATA = СВОЯ_ПАПКА;

const КОРЕНЬ = path.join(__dirname, '..');
const ЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;

if (ЛОМАТЬ) {
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: подменяем срезПоСписку на срезДляИгрока — ' +
              'список друзей перестаёт учитываться, посторонний утекает в ответ ***');
}

const рейтинг = require(path.join(КОРЕНЬ, 'server', 'рейтинг.js'));

/* При флаге --сломать подменяем функцию в кеше Node на срез по ВСЕЙ
   таблице игры (без фильтра по списку друзей) — ровно тот баг, который
   тест обязан заметить. */
if (ЛОМАТЬ) {
  рейтинг.срезПоСписку = function (игра, номер) {
    return рейтинг.срезДляИгрока(игра, номер);
  };
}

let проверок = 0;
const провалы = [];

function проверить(условие, что) {
  проверок++;
  if (!условие) {
    провалы.push(что);
    console.log('  ПРОВАЛ: ' + что);
  }
}

const ИГРА = 'дурак';

/* --------- Персонажи теста --------- */

const МЕНЯ = 4001;             // спрашивающий срез
const ДРУГ_А = 4002;           // друг с самым большим счётом (20)
const ДРУГ_Б = 4003;           // друг со средним счётом (5)
const ДРУГ_В = 4004;           // друг с нулевым счётом, но с записью (0)
const ДРУГ_БЕЗ_ЗАПИСИ = 4005;  // в списке друзей, но ни разу не играл — записи нет
const ПОСТОРОННИЙ = 4006;      // не входит в список друзей, но играл и есть в таблице
const НИКОГДА_НЕ_ИГРАЛ = 4007; // сам спрашивающий, у которого нет записи вообще

/* --------- Засев данных --------- */

function засеятьДанные() {
  console.log('\nЗасеиваем рейтинг нужными партиями...');

  /* МЕНЯ побеждает ПОСТОРОННЕГО: МЕНЯ +10, ПОСТОРОННИЙ +0. */
  рейтинг.учестьПартию(ИГРА, [
    { номер: МЕНЯ, имя: 'Меня', этоБот: false, победил: true, ничья: false },
    { номер: ПОСТОРОННИЙ, имя: 'Посторонний', этоБот: false, победил: false, ничья: false }
  ]);

  /* ДРУГ_А побеждает ПОСТОРОННЕГО: ДРУГ_А +10 (итого 10). */
  рейтинг.учестьПартию(ИГРА, [
    { номер: ДРУГ_А, имя: 'ДругА', этоБот: false, победил: true, ничья: false },
    { номер: ПОСТОРОННИЙ, имя: 'Посторонний', этоБот: false, победил: false, ничья: false }
  ]);

  /* ДРУГ_А побеждает МЕНЯ: ДРУГ_А +10 (итого 20), МЕНЯ +0 (остаюсь на 10). */
  рейтинг.учестьПартию(ИГРА, [
    { номер: ДРУГ_А, имя: 'ДругА', этоБот: false, победил: true, ничья: false },
    { номер: МЕНЯ, имя: 'Меня', этоБот: false, победил: false, ничья: false }
  ]);

  /* ДРУГ_Б и ПОСТОРОННИЙ сыграли вничью: ДРУГ_Б +5 (итого 5), ПОСТОРОННИЙ +5. */
  рейтинг.учестьПартию(ИГРА, [
    { номер: ДРУГ_Б, имя: 'ДругБ', этоБот: false, победил: false, ничья: true },
    { номер: ПОСТОРОННИЙ, имя: 'Посторонний', этоБот: false, победил: false, ничья: true }
  ]);

  /* ПОСТОРОННИЙ побеждает ДРУГ_В: ДРУГ_В +0, но запись у него уже
     появилась (партий: 1, очки: 0) — ровно нужный случай «в таблице,
     но с нулём очков», отличный от «записи вовсе нет». */
  рейтинг.учестьПартию(ИГРА, [
    { номер: ПОСТОРОННИЙ, имя: 'Посторонний', этоБот: false, победил: true, ничья: false },
    { номер: ДРУГ_В, имя: 'ДругВ', этоБот: false, победил: false, ничья: false }
  ]);

  console.log('Ожидаемые очки: МЕНЯ=10, ДРУГ_А=20, ДРУГ_Б=5, ДРУГ_В=0 (в таблице), ' +
              'ДРУГ_БЕЗ_ЗАПИСИ — записи нет вовсе, ПОСТОРОННИЙ=5 (в таблице, но не друг)\n');
}

/* --------- Сама проверка --------- */

function проверитьБазовыйСлучай() {
  console.log('1. Базовый случай: список друзей [ДРУГ_А, ДРУГ_Б, ДРУГ_В], посторонний не в списке');
  const срез = рейтинг.срезПоСписку(ИГРА, МЕНЯ, [ДРУГ_А, ДРУГ_Б, ДРУГ_В]);

  проверить(typeof срез === 'object' && срез !== null, 'ответ — объект');
  проверить(срез.всего === 4, 'всего участников = 4 (я + 3 друга с записями), было: ' + срез.всего);
  проверить(срез.яВТаблице === true, 'яВТаблице = true');
  проверить(typeof срез.я === 'object' && срез.я !== null, 'я — объект');
  if (срез.я) проверить(срез.я.очки === 10, 'мои очки = 10, было: ' + срез.я.очки);

  const весьТекст = JSON.stringify(срез);
  проверить(весьТекст.indexOf('Посторонний') === -1,
    'посторонний не входит ни в верхушку, ни в вокругМеня (искали имя "Посторонний")');

  /* Посторонний присутствует в таблице этой же игры — если бы фильтр
     не работал, имя проскочило бы в общий JSON ответа. */
  проверить(Array.isArray(срез.верхушка), 'верхушка — массив');
  if (Array.isArray(срез.верхушка)) {
    const именаВерхушки = срез.верхушка.map(function (стр) { return стр.имя; });
    проверить(именаВерхушки.indexOf('Посторонний') === -1,
      'имени "Посторонний" нет в верхушке (было: ' + именаВерхушки.join(', ') + ')');
  }
}

function проверитьДругаБезЗаписи() {
  console.log('2. Друг из списка, который ни разу не играл — должен молча пропуститься');
  const срез = рейтинг.срезПоСписку(ИГРА, МЕНЯ, [ДРУГ_А, ДРУГ_БЕЗ_ЗАПИСИ]);

  проверить(срез.всего === 2, 'всего = 2 (я + ДРУГ_А, ДРУГ_БЕЗ_ЗАПИСИ пропущен), было: ' + срез.всего);
  const весьТекст = JSON.stringify(срез);
  проверить(весьТекст.indexOf('ДругБезЗаписи') === -1,
    'имя игрока без записи не всплывает в ответе');
}

function проверитьДубли() {
  console.log('3. Дубль номера в списке друзей — не должен задваивать запись');
  const срез = рейтинг.срезПоСписку(ИГРА, МЕНЯ, [ДРУГ_А, ДРУГ_А, ДРУГ_Б]);

  проверить(срез.всего === 3, 'всего = 3 (я + ДРУГ_А один раз + ДРУГ_Б), было: ' + срез.всего);
  const считаемА = срез.верхушка.filter(function (стр) { return стр.имя === 'ДругА'; }).length;
  проверить(считаемА === 1, 'ДругА встречается в верхушке ровно один раз, было: ' + считаемА);
}

function проверитьСебяВСпискеДрузей() {
  console.log('4. Собственный номер игрока внутри списка друзей — не должен задваивать «я»');
  const срез = рейтинг.срезПоСписку(ИГРА, МЕНЯ, [МЕНЯ, ДРУГ_А]);

  проверить(срез.всего === 2, 'всего = 2 (я + ДРУГ_А, свой номер в списке не задвоил), было: ' + срез.всего);
  const считаемМеня = срез.верхушка.filter(function (стр) { return стр.этоЯ === true; }).length;
  проверить(считаемМеня === 1, '«я» встречается в верхушке ровно один раз, было: ' + считаемМеня);
}

function проверитьПустойСписок() {
  console.log('5. Пустой список друзей [] — должен вернуть только меня, без падения');
  const срез = рейтинг.срезПоСписку(ИГРА, МЕНЯ, []);

  проверить(срез.всего === 1, 'всего = 1 (только я), было: ' + срез.всего);
  проверить(срез.яВТаблице === true, 'яВТаблице = true');
  проверить(срез.я && срез.я.очки === 10, 'мои очки = 10 при пустом списке, было: ' + (срез.я && срез.я.очки));
}

function проверитьНеМассив() {
  console.log('6. Не-массив вместо списка друзей (undefined, null) — не должен ронять сервер');

  let сбойУпал = false;
  let срезUndefined = null;
  try {
    срезUndefined = рейтинг.срезПоСписку(ИГРА, МЕНЯ, undefined);
  } catch (беда) {
    сбойУпал = true;
    console.log('     упало на undefined: ' + беда.message);
  }
  проверить(!сбойУпал, 'вызов с undefined не бросает исключение');
  if (срезUndefined) {
    проверить(срезUndefined.всего === 1, 'с undefined в ответе только я, было: ' + срезUndefined.всего);
  }

  сбойУпал = false;
  let срезNull = null;
  try {
    срезNull = рейтинг.срезПоСписку(ИГРА, МЕНЯ, null);
  } catch (беда) {
    сбойУпал = true;
    console.log('     упало на null: ' + беда.message);
  }
  проверить(!сбойУпал, 'вызов с null не бросает исключение');
  if (срезNull) {
    проверить(срезNull.всего === 1, 'с null в ответе только я, было: ' + срезNull.всего);
  }
}

function проверитьНетУтечкиНомера() {
  console.log('7. Номер Telegram не должен уходить наружу ни в одном сценарии');
  const сценарии = [
    рейтинг.срезПоСписку(ИГРА, МЕНЯ, [ДРУГ_А, ДРУГ_Б, ДРУГ_В]),
    рейтинг.срезПоСписку(ИГРА, МЕНЯ, []),
    рейтинг.срезПоСписку(ИГРА, МЕНЯ, undefined),
    рейтинг.срезПоСписку(ИГРА, ПОСТОРОННИЙ, [МЕНЯ, ДРУГ_А])
  ];
  for (const срез of сценарии) {
    const текст = JSON.stringify(срез);
    проверить(текст.indexOf('"номер"') === -1,
      'ключа "номер" нет в JSON ответа (проверили: ' + текст.slice(0, 60) + '...)');
  }
}

function проверитьСортировку() {
  console.log('8. Сортировка по убыванию очков: ДРУГ_А (20) выше ДРУГ_Б (5) выше ДРУГ_В (0)');
  const срез = рейтинг.срезПоСписку(ИГРА, МЕНЯ, [ДРУГ_А, ДРУГ_Б, ДРУГ_В]);

  проверить(Array.isArray(срез.верхушка) && срез.верхушка.length >= 4,
    'в верхушке достаточно строк для проверки порядка (я + 3 друга помещаются, лимит верхушки — 5)');

  if (Array.isArray(срез.верхушка)) {
    const порядокОчков = срез.верхушка.map(function (стр) { return стр.очки; });
    console.log('     очки по местам: ' + порядокОчков.join(', '));
    let поУбыванию = true;
    for (let i = 1; i < порядокОчков.length; i++) {
      if (порядокОчков[i] > порядокОчков[i - 1]) поУбыванию = false;
    }
    проверить(поУбыванию, 'очки в верхушке идут по невозрастанию (было: ' + порядокОчков.join(', ') + ')');

    const местоА = срез.верхушка.findIndex(function (стр) { return стр.имя === 'ДругА'; });
    const местоБ = срез.верхушка.findIndex(function (стр) { return стр.имя === 'ДругБ'; });
    const местоВ = срез.верхушка.findIndex(function (стр) { return стр.имя === 'ДругВ'; });

    проверить(местоА !== -1 && местоБ !== -1 && местоВ !== -1,
      'все три друга нашлись в верхушке по имени');
    if (местоА !== -1 && местоБ !== -1) {
      проверить(местоА < местоБ, 'ДругА (20 очков) стоит выше ДругБ (5 очков)');
    }
    if (местоБ !== -1 && местоВ !== -1) {
      проверить(местоБ < местоВ, 'ДругБ (5 очков) стоит выше ДругВ (0 очков)');
    }

    const записьА = срез.верхушка[местоА];
    const записьБ = срез.верхушка[местоБ];
    const записьВ = срез.верхушка[местоВ];
    if (записьА) проверить(записьА.очки === 20, 'у ДругА реально 20 очков, было: ' + записьА.очки);
    if (записьБ) проверить(записьБ.очки === 5, 'у ДругБ реально 5 очков, было: ' + записьБ.очки);
    if (записьВ) проверить(записьВ.очки === 0, 'у ДругВ реально 0 очков, было: ' + записьВ.очки);
  }
}

function проверитьФормуОтвета() {
  console.log('9. Форма ответа {всего, яВТаблице, я, верхушка, вокругМеня} всегда на месте');

  const сценарии = [
    { имя: 'базовый', срез: рейтинг.срезПоСписку(ИГРА, МЕНЯ, [ДРУГ_А, ДРУГ_Б]) },
    { имя: 'пустой список', срез: рейтинг.срезПоСписку(ИГРА, МЕНЯ, []) },
    { имя: 'спрашивающий без записи', срез: рейтинг.срезПоСписку(ИГРА, НИКОГДА_НЕ_ИГРАЛ, [ДРУГ_А]) },
    { имя: 'не-массив (undefined)', срез: рейтинг.срезПоСписку(ИГРА, МЕНЯ, undefined) }
  ];

  for (const пример of сценарии) {
    const срез = пример.срез;
    проверить(typeof срез.всего === 'number', пример.имя + ': поле всего — число');
    проверить(typeof срез.яВТаблице === 'boolean', пример.имя + ': поле яВТаблице — булево');
    проверить(Array.isArray(срез.верхушка), пример.имя + ': поле верхушка — массив');
    проверить(Array.isArray(срез.вокругМеня), пример.имя + ': поле вокругМеня — массив');
    проверить('я' in срез, пример.имя + ': поле я присутствует (может быть null)');
  }

  /* Отдельно: спрашивающий, у которого вообще нет записи в таблице —
     яВТаблице должно быть false, я — null, без падения при чтении. */
  const срезБезМеня = рейтинг.срезПоСписку(ИГРА, НИКОГДА_НЕ_ИГРАЛ, [ДРУГ_А, ДРУГ_Б]);
  проверить(срезБезМеня.яВТаблице === false, 'спрашивающий без записи: яВТаблице = false');
  проверить(срезБезМеня.я === null, 'спрашивающий без записи: я = null');
  проверить(срезБезМеня.всего === 2, 'спрашивающий без записи: всего = 2 (друзья с записями, сам не считается)');
}

