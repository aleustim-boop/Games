/* Ответ двери, но не дольше полутора секунд. Испорченная копия может
   оставить обещание висеть навсегда — тогда node молча вышел бы посреди
   прогона, и остальные поломки не проверились бы. Зависшая дверь —
   провал проверки ({ висит: true } не совпадёт ни с одним ожиданием). */
function ответДвери(обещание) {
  return Promise.race([обещание, new Promise(function (готово) {
    const сторож = setTimeout(function () { готово({ висит: true }); }, 1500);
    обещание.then(function () { clearTimeout(сторож); }, function () { clearTimeout(сторож); });
  })]);
}

