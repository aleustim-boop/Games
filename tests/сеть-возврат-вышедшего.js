/* ---------- Столы — настоящими комнатами ---------- */

let номерАдреса = 0;
let номерТелеграма = 71000;
const созданныеКоды = [];

/**
 * Стол на «мест» мест, все места — люди. Страница садится ПОСЛЕДНЕЙ
 * (как уходящий в tests/возврат-вышедшего-сервер.js). начать=false —
 * стол ждёт в прихожей. Ответ: { код, комната, пропуски[], места[] }.
 */
function собратьСтол(мест, начать) {
  номерАдреса++;
  номерТелеграма += 10;
  const создана = комнаты.создатьКомнату('10.7.' + Math.floor(номерАдреса / 200) + '.' + (номерАдреса % 200 + 1),
    { имя: 'Аня', телеграм: номерТелеграма, игра: 'дурак', мест: мест });
  if (!создана.ок) throw new Error('комната не создалась: ' + создана.причина);
  созданныеКоды.push(создана.код);
  const хозяин = комнаты.найтиИгрока(создана.код, создана.пропуск);
  const пропуски = [создана.пропуск];
  const места = [хозяин.ктоЯ];
  for (let i = 1; i < мест; i++) {
    const вход = комнаты.войтиВКомнату(создана.код, { имя: 'Гость' + i, телеграм: номерТелеграма + i });
    if (!вход.ок) throw new Error('гость не вошёл: ' + вход.причина);
    пропуски.push(вход.пропуск);
    места.push(комнаты.найтиИгрока(создана.код, вход.пропуск).ктоЯ);
  }
  if (начать && хозяин.комната.этап === 'ожидание') {
    const начали = комнаты.сделатьХод(хозяин.комната, хозяин.ктоЯ, { действие: 'начать' });
    if (!начали.принято) throw new Error('партия не началась: ' + начали.причина);
  }
  return { код: создана.код, комната: хозяин.комната, пропуски: пропуски, места: места };
}

