/* Старое поведение: сдача не откладывает торги за здание, и они
   начинаются заново. */
const ПОРЧА_БЫЛО = '        g.queue[0].paused = g.auction;\n';
const внутри = (папка, корень) => {
  const от = path.relative(path.resolve(корень), path.resolve(папка));
  return !от.startsWith('..') && !path.isAbsolute(от);
};
function сделатьЛомающуюКопию(папкаКопии) {
  const текст = fs.readFileSync(ПРАВИЛА_ПРОЕКТА, 'utf8').replace(/\r\n/g, '\n');
  const вхождений = текст.split(ПОРЧА_БЫЛО).length - 1;
  if (вхождений !== 1) throw new Error('место порчи устарело: ожидалось ровно одно вхождение, нашлось ' + вхождений);
  const папка = path.resolve(папкаКопии);
  if (внутри(папка, КОРЕНЬ)) throw new Error('копию нельзя класть внутрь проекта: ' + папка);
  if (!внутри(папка, os.tmpdir())) throw new Error('копия — только во временной папке системы (' + os.tmpdir() + '): ' + папка);
  fs.mkdirSync(папка, { recursive: true });
  fs.copyFileSync(path.join(КОРЕНЬ, 'игры', 'монополия', 'монополия-данные.js'), path.join(папка, 'монополия-данные.js'));
  const копия = path.join(папка, 'монополия-правила.js');
  fs.writeFileSync(копия, текст.replace(ПОРЧА_БЫЛО, ''), 'utf8');
  return копия;
}

