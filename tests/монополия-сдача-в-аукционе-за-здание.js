/* =====================================================================
   СДАЧА ПОСРЕДИ АУКЦИОНА ЗА ПОСЛЕДНЕЕ ЗДАНИЕ БАНКА НЕ ВЕШАЕТ ПАРТИЮ.

   Что чинили (см. задание). Раньше: игрок сдаётся (type: "surrender")
   посреди аукциона за ПОСЛЕДНЕЕ здание банка — g.auction обнулялся, а
   задание аукциона в очереди перезапускалось со старым списком
   участников (сдавшийся оставался в eligible) и БЕЗ kind/targets/bids,
   так что ставку никто сделать не мог, и партия вставала намертво.

   Теперь auction() при каждом запуске (и при перезапуске после сдачи)
   фильтрует выбывших из eligible и заново заводит kind/targets/bids
   для аукциона за здание. Если претендентов совсем не осталось —
   задание снимается с очереди, событие auctionEmpty, игра идёт дальше.
   buildingWinner() умеет достроить ставку лидера даже если у партии
   (сохранённой до этого обновления) нет поля a.bids вовсе.

   Проверяем здесь (только node, чистые правила, без браузера и сервера):
     А) сдаётся кандидат, который не актёр и не лидер — партия не виснет
     Б) сдаётся текущий актёр — ход переходит к живому участнику
     В) сдаётся лидер ставки — после перезапуска аукцион чистый
     Г) сдаются подряд ВСЕ кандидаты — здание остаётся в банке (auctionEmpty)
     Д) старое сохранение без a.auction.bids — лидер всё равно получает здание
     Е) дословный текст отказа строить последнее здание в чужой buy/debt
     Ж) обычная сдача вне аукциона по-прежнему работает (регресс)

   Запуск:
       node tests/монополия-сдача-в-аукционе-за-здание.js

   Ломающий запуск (обязан покраснеть; настоящий файл проекта не
   трогаем — работаем с копией во временной папке):
       node tests/монополия-сдача-в-аукционе-за-здание.js <путь-к-копии>
   Копия: в auction() убрать фильтр выбывших у eligible (вернуть
   `task.eligible || alive(g)` без `.filter(i => !g.players[i].out)`)
   И убрать заведение kind/targets/bids для аукциона за здание — то
   есть буквально вернуть старое (сломанное) поведение функции.
   ===================================================================== */

