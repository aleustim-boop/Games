const own = (g, p, ids, level = 0) =>
  ids.forEach((id) => Object.assign(g.properties[id], { owner: p, level }));

/* Стол для проверок: у игроков 0 (А), 1 (Б) и 2 (В) — по своему целому
   кварталу на уровне 0, все трое могут построить следующий (последний
   в банке) дом. В банке остаётся ровно 1 дом (раскладка подтверждена
   уже работающим тестом tests/монополия-аукцион-за-здание-не-вешает.js,
   те же клетки и те же заполнители).
   Если игроков в партии 4 и больше — общий ход держит "посторонний"
   игрок (индекс 3), который сам никогда не строит и не участвует в
   аукционе за здание: так сдача любого из кандидатов А/Б/В не путает
   "чей сейчас общий ход" с "кто выбыл из торгов". Для сценария, где
   сдаются ВСЕ кандидаты подряд, нужен ещё один посторонний (индекс 4),
   иначе после третьей сдачи в живых остался бы только один игрок и
   партия завершилась бы победой раньше, чем мы успеем проверить
   опустевший аукцион. */
function стол(seed, n = 3) {
  const g = P.create(n, seed);
  g.turn = n >= 4 ? 3 : 0;
  g.phase = 'manage';
  g.queue = [];
  own(g, 0, [16, 18, 19], 0); // А
  own(g, 1, [6, 8, 9], 0); // Б
  own(g, 2, [11, 13, 14], 0); // В
  [21, 23, 24].forEach((id) => {
    g.properties[id].level = 4;
  });
  [26, 27, 29].forEach((id) => {
    g.properties[id].level = 4;
  });
  g.properties[37].level = 4;
  g.properties[39].level = 3;
  return g;
}

/* Сдача игрока p + "доигрывание" чужих (не строительных) аукционов,
   которые бывший кандидат оставляет после себя: у сдавшегося есть
   свой целый квартал, и bankrupt() выставляет эти улицы на отдельный,
   обычный (не building) аукцион. Идут они ПОСЛЕ торгов за здание, так
   что сразу после сдачи пропускать обычно нечего; пропуск нужен, когда
   торги за здание уже кончились (сдался последний кандидат), и после
   победы на торгах за здание — пасуем за всех, пока аукционы участков
   не кончатся. */
function пропуститьЧужиеАукционы(g) {
  let шагов = 0;
  while (g.phase === 'auction' && !g.auction.building && шагов++ < 40) {
    const актёр = P.who(g);
    P.action(g, актёр, { type: 'pass' });
  }
}
function сдаться(g, p) {
  P.action(g, p, { type: 'surrender' });
  пропуститьЧужиеАукционы(g);
}

function найтиСобытие(g, kind, доп = {}) {
  return g.events.find(
    (e) => e.kind === kind && Object.keys(доп).every((ключ) => e[ключ] === доп[ключ]),
  );
}

function проверитьAssert(g, название) {
  try {
    P.assert(g);
    отметить(true, название + ': итоговое состояние партии не нарушает внутренних правил (assert)');
  } catch (e) {
    отметить(false, название + ': assert упал: ' + e.message);
  }
}

