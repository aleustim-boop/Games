/* ---------------------------------------------------------------------
   1. «Играть с ботом» не обгоняет открытый стол
   --------------------------------------------------------------------- */
async function проверитьБотаИСтол() {
  console.log('1. «Играть с ботом»: открытый стол важнее бота');

  /* А. Стол открыли уже после того, как человек встал ждать. */
  const ключА = await встатьЖдать(9600001, 'Алла');
  const столА = await создатьОткрытыйСтол(9600002, 'Борис');
  проверить(людей(столА) === 1, 'А: опора — за открытым столом Бориса пока один');
  const а = await нажатьБота(9600001, 'Алла', ключА);
  проверить(а.тело.статус === 'свели' && а.тело.код === столА,
    'А: Алла по кнопке бота села за стол Бориса, а не к боту (' + JSON.stringify(а.тело).replace(/"пропуск":"[^"]*"/, '"пропуск":"…"') + ')');
  проверить(людей(столА) === 2, 'А: за столом Бориса теперь двое людей');
  проверить(JSON.stringify(Object.keys(а.тело).sort()) === JSON.stringify(['код', 'пропуск', 'статус'].sort()),
    'А: вид ответа — как у обычного подбора: только статус, код, пропуск (' + Object.keys(а.тело).join(',') + ')');
  проверить(typeof а.тело.пропуск === 'string' && а.тело.пропуск.length > 0, 'А: пропуск выдан');
  const опрос = await спросить('/подбор-новости', { ключОжидания: ключА });
  проверить(опрос.тело.статус === 'не_найдено', 'А: из очереди Алла снята — опрос по её ключу «не_найдено» (' + JSON.stringify(опрос.тело) + ')');
  const повтор = await нажатьБота(9600001, 'Алла', ключА);
  проверить(повтор.тело.статус !== 'свели', 'А: повторное нажатие второго стола не заводит');
  проверить(людей(столА) === 2, 'А: после повтора за столом Бориса по-прежнему двое');

  /* Б. Открытого стола нет — как раньше, бот в новой комнате. */
  const ключБ = await встатьЖдать(9600003, 'Вера');
  const б = await нажатьБота(9600003, 'Вера', ключБ);
  проверить(б.тело.статус === 'свели' && Boolean(б.тело.код) && б.тело.код !== столА,
    'Б: стола нет — Вера получила свою комнату (с ботом)');
  проверить(людей(б.тело.код) === 1, 'Б: в комнате Веры один человек, соперник — бот');

  /* В. Правила не те: стол переводной, а Глеб ждёт подкидного. */
  const столВ = await создатьОткрытыйСтол(9600004, 'Дина', { переводной: true });
  const ключВ = await встатьЖдать(9600005, 'Глеб', { переводной: false });
  const в = await нажатьБота(9600005, 'Глеб', ключВ);
  проверить(в.тело.статус === 'свели' && в.тело.код !== столВ,
    'В: правила не совпали — к столу Дины не посадили, Глеб получил своего бота');
  проверить(людей(столВ) === 1, 'В: за столом Дины по-прежнему один');
}

/* ---------------------------------------------------------------------
   3. Жалоба на диск — не чаще раза в 15 минут
   --------------------------------------------------------------------- */
function проверитьЖалобуНаДиск() {
  console.log('3. Письма турнира: жалоба «память не записалась» не чаще раза в 15 минут');
  const МИНУТА = 60 * 1000;
  const пути = path.join(КОРЕНЬ, 'server', 'турнир-письма.js');
  delete require.cache[require.resolve(пути)];
  const письма = require(пути);

  /* Диск «сломан»: на месте папки лежит файл, создать папку внутри нельзя. */
  const папкаДиска = fs.mkdtempSync(path.join(os.tmpdir(), 'ночь-2-диск-'));
  // Уборка по выходу из процесса — сработает и при провале проверки.
  process.on('exit', function () {
    try { fs.rmSync(папкаДиска, { recursive: true, force: true }); } catch (ошибка) { /* не мешаем итогу */ }
  });
  const файлВместоПапки = path.join(папкаДиска, 'файл.txt');
  fs.writeFileSync(файлВместоПапки, 'x', 'utf8');
  let часы = Date.UTC(2026, 9, 5, 12, 0, 0);
  письма.подключить({
    турниры: турниры,
    этоЛичина: function () { return false; },
    адресИгры: 'https://игры.пример.рф/',
    папка: path.join(файлВместоПапки, 'внутри'),
    сейчас: function () { return часы; }
  });

  /* Один записавшийся человек: каждое напоминание пытается записать память и не может. */
  const полдень = Date.UTC(2026, 9, 5, 9, 0, 0);
  турниры.записать(9600101, 'Лена', полдень);
  const окноНапоминаний = Date.UTC(2026, 9, 5, 16, 50, 0);   // 19:50 по Москве

  const жалобы = [];
  console.error = function (текст) { жалобы.push(String(текст)); };
  let ушлиПисьма = 0;
  function минута() {
    ушлиПисьма += письма.письмаНапоминания(окноНапоминаний).length;
    часы += МИНУТА;
  }
  try {
    минута();   // 0-я минута
    проверить(жалобы.length === 1, 'первая жалоба — сразу (' + жалобы.length + ')');
    проверить(!/Повторов/.test(жалобы[0] || ''), 'в первой жалобе нет числа пропущенных повторов');
    for (let к = 1; к <= 14; к++) минута();   // минуты 1..14
    проверить(жалобы.length === 1, 'за следующие 14 минут жалоб не прибавилось (' + жалобы.length + ')');
    минута();   // 15-я минута
    проверить(жалобы.length === 2, 'на 15-й минуте — вторая жалоба (' + жалобы.length + ')');
    проверить(/Повторов[^0-9]*14\b/.test(жалобы[1] || ''), 'во второй жалобе — число пропущенных повторов 14 (' + (жалобы[1] || '') + ')');
    for (let к = 16; к <= 29; к++) минута();
    проверить(жалобы.length === 2, 'между 16-й и 29-й минутами снова тихо (' + жалобы.length + ')');
    минута();   // 30-я
    проверить(жалобы.length === 3, 'на 30-й минуте — третья жалоба (' + жалобы.length + ')');
    проверить(ушлиПисьма === 0, 'пока диск сломан, письма не уходят (' + ушлиПисьма + ')');
    проверить(жалобы.every(function (ж) { return !/ENOTDIR|ENOENT|EEXIST|EPERM|EACCES/.test(ж); }), 'в жалобах нет текста системной ошибки');
  } finally {
    console.error = настоящаяОшибка;
  }
}

