function сделатьИспорченнуюКопию() {
  const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'ночь-сервер-2-копия-'));
  const данныеПроекта = path.join(КОРЕНЬ_ПРОЕКТА, 'server', 'данные');
  fs.cpSync(path.join(КОРЕНЬ_ПРОЕКТА, 'server'), path.join(врем, 'server'), {
    recursive: true,
    filter: function (откуда) { return откуда !== данныеПроекта && !откуда.startsWith(данныеПроекта + path.sep); }
  });
  require('./пути-проекта.js').скопироватьКод(КОРЕНЬ_ПРОЕКТА, врем, 'js');

  const порча = ПОРЧИ[ИМЯ_ПОРЧИ];
  const файл = path.join(врем, 'server', порча.файл);
  const текст = fs.readFileSync(файл, 'utf8').replace(/\r\n/g, '\n');
  if (текст.split(порча.было).length - 1 !== 1) {
    console.log('ЛОМАЮЩИЙ ЗАПУСК НЕ СОСТОЯЛСЯ: в копии server/' + порча.файл + ' не найдено ровно одно место для порчи (' + ИМЯ_ПОРЧИ + ').');
    fs.rmSync(врем, { recursive: true, force: true });
    process.exit(2);
  }
  fs.writeFileSync(файл, текст.split(порча.было).join(порча.стало), 'utf8');
  return врем;
}

