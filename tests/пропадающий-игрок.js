'use strict';

/* =====================================================================
   Игрок, который умеет пропасть со связи и вернуться.

   Зачем он нужен. Проверить надпись «нет связи» над столом иначе нечем:
   обычный помощник (tests/подсадить-игрока.js) либо играет, либо его
   убивают насовсем — и назад он уже не приходит, потому что при новом
   входе получает новый пропуск и новое место. А проверять надо ровно
   обратное: человек уехал в метро, надпись появилась, человек вернулся —
   надпись обязана пропасть.

   Этот помощник входит один раз, запоминает свой пропуск и дальше просто
   перестаёт стучаться на сервер на заданное время. Для сервера это
   выглядит точно как выключенный интернет: место занято, но молчит.
   Потом он возвращается с тем же пропуском и доигрывает.

   Как запускать (сервер комнат поднят, комната создана в браузере):

       node tests/пропадающий-игрок.js КОД "Имя" 8790 молчать 20 25

   Числа в конце: через сколько секунд после начала пропасть и на сколько
   секунд замолчать. Не сказали — играет обычным игроком и не пропадает.

       node tests/пропадающий-игрок.js КОД "Имя" 8790 молчать 20 0

   Ноль вторым числом — пропасть и больше не возвращаться (но процесс
   не умирает, а держит место занятым: так удобно ждать, когда сервер
   через три минуты посадит на это место бота).
   ===================================================================== */

const http = require('http');

const КОД = (process.argv[2] || '').toUpperCase();
const ИМЯ = process.argv[3] || 'Напарник';
const ПОРТ = Number(process.argv[4]) || 8790;
const ХОЗЯИН = '127.0.0.1';

// Разбор слов «молчать N M»
const где = process.argv.indexOf('молчать');
const ПРОПАСТЬ_ЧЕРЕЗ = где === -1 ? 0 : Math.round(Number(process.argv[где + 1] || 0) * 1000);
const МОЛЧАТЬ_СЕКУНД = где === -1 ? 0 : Math.round(Number(process.argv[где + 2] || 0) * 1000);

if (!КОД) {
  console.error('Скажите код комнаты: node tests/пропадающий-игрок.js КОД "Имя" 8790 молчать 20 25');
  process.exit(1);
}

function спросить(путь, тело) {
  return new Promise((готово, беда) => {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, (ответ) => {
      let текст = '';
      ответ.setEncoding('utf8');
      ответ.on('data', (к) => { текст += к; });
      ответ.on('end', () => {
        let р = null;
        try { р = JSON.parse(текст); } catch (сбой) { р = { сырое: текст }; }
        готово({ код: ответ.statusCode, тело: р });
      });
    });
    запрос.setTimeout(40000, () => запрос.destroy(new Error('сервер молчит')));
    запрос.on('error', беда);
    запрос.end(данные);
  });
}

const пауза = (мс) => new Promise((r) => setTimeout(r, мс));
const час = () => new Date().toTimeString().slice(0, 8);

/* Отказали на подкидывание — в этом подходе больше не лезем, закрываем
   его словом «Пас». Помощник простой и всех ограничений не считает. */
let подкидыватьБольшеНеПробуем = false;

function бьёт(чем, что, козырь) {
  if (чем.масть === что.масть) return чем.вес > что.вес;
  return чем.масть === козырь && что.масть !== козырь;
}

/** Что бы сделал на этом столе самый простой игрок. Взято из подсадить-игрока.js. */
function решить(вид) {
  const рука = вид.мояРука || [];
  const стол = вид.стол || [];
  const козырь = вид.козырь;
  const яЗащищаюсь = вид.яОтбиваюсь === undefined
    ? (вид.фаза === 'защита' && вид.яХожу)
    : вид.яОтбиваюсь;

  if (яЗащищаюсь && !вид.берут) {
    let номер = -1;
    for (let i = 0; i < стол.length; i++) { if (!стол[i].защита) { номер = i; break; } }
    if (номер < 0) return null;
    const атака = стол[номер].атака;
    const годные = рука.map((к, i) => ({ к, i }))
      .filter((п) => атака && бьёт(п.к, атака, козырь))
      .sort((а, б) => (а.к.масть === козырь ? 1 : 0) - (б.к.масть === козырь ? 1 : 0) || а.к.вес - б.к.вес);
    if (годные.length) return { действие: 'отбить', пара: номер, карта: годные[0].i };
    return { действие: 'беру' };
  }

  if (вид.яХожу) {
    if (!рука.length) return стол.length ? { действие: 'бито' } : null;
    if (!стол.length) {
      const порядок = рука.map((к, i) => ({ к, i }))
        .sort((а, б) => (а.к.масть === козырь ? 1 : 0) - (б.к.масть === козырь ? 1 : 0) || а.к.вес - б.к.вес);
      return { действие: 'ходить', карта: порядок[0].i };
    }
    if (подкидыватьБольшеНеПробуем) return { действие: 'бито' };
    const веса = new Set();
    стол.forEach((п) => { if (п.атака) веса.add(п.атака.вес); if (п.защита) веса.add(п.защита.вес); });
    const годная = рука.findIndex((к) => веса.has(к.вес) && к.масть !== козырь);
    if (годная >= 0) return { действие: 'ходить', карта: годная };
    return { действие: 'бито' };
  }
  return null;
}

async function главная() {
  const вход = await спросить('/войти', { код: КОД, имя: ИМЯ });
  if (вход.код !== 200) {
    console.error('Войти не вышло: ' + вход.код + ' ' + JSON.stringify(вход.тело));
    process.exit(1);
  }
  const пропуск = вход.тело.пропуск;
  console.log(час() + ' сел за стол под именем «' + ИМЯ + '», комната ' + КОД);

  const начало = Date.now();
  let ужеПропадал = false;

  for (let шаг = 0; шаг < 100000; шаг++) {
    // Пора пропасть?
    if (ПРОПАСТЬ_ЧЕРЕЗ > 0 && !ужеПропадал && Date.now() - начало >= ПРОПАСТЬ_ЧЕРЕЗ) {
      ужеПропадал = true;
      if (МОЛЧАТЬ_СЕКУНД > 0) {
        console.log(час() + ' ПРОПАЛ СО СВЯЗИ на ' + (МОЛЧАТЬ_СЕКУНД / 1000) + ' с');
        await пауза(МОЛЧАТЬ_СЕКУНД);
        console.log(час() + ' СВЯЗЬ ВЕРНУЛАСЬ — играю дальше');
      } else {
        console.log(час() + ' ПРОПАЛ СО СВЯЗИ насовсем (место держу, но молчу)');
        await пауза(30 * 60 * 1000);
        return;
      }
    }

    const с = await спросить('/состояние', { код: КОД, пропуск });
    if (с.код !== 200) { console.log(час() + ' комната пропала: ' + с.код); break; }
    const вид = с.тело.состояние || с.тело;
    if (вид.завершена) {
      console.log(час() + ' партия окончена, итог для меня: ' + вид.итог);
      await спросить('/ход', { код: КОД, пропуск, действие: 'ещё' });
      await пауза(1500);
      continue;
    }
    if (!(вид.стол || []).length) подкидыватьБольшеНеПробуем = false;
    const намерение = решить(вид);
    if (!намерение) { await пауза(300); continue; }
    const о = await спросить('/ход', Object.assign({ код: КОД, пропуск }, намерение));
    if (о.тело && о.тело.принято === false) {
      if (намерение.действие === 'ходить') подкидыватьБольшеНеПробуем = true;
      await пауза(500);
    }
    await пауза(250);
  }
}

главная().catch((сбой) => { console.error('Сорвалось: ' + сбой.message); process.exitCode = 1; });
