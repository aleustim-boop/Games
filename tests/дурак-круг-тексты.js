/* =====================================================================
   ТЕКСТЫ ИТОГА ДЛЯ ПРАВИЛА «ВЕЧНЫЙ КРУГ» (игры/дурак/game.js).

   Что проверяет. Партия, зашедшая по кругу (расклад повторился трижды —
   см. tests/дурак-вечный-круг.js, там проверено само правило «кто дурак»),
   должна честно рассказать об этом на экране итога:
     - заголовок остаётся обычным («Вы выиграли!» / «Вы проиграли» /
       «Ничья» — или свой заголовок у компании), меняться ему незачем;
     - пояснение получает вставку «Партия пошла по кругу — расклад
       повторился трижды. Дурак тот, у кого больше карт: <имя> (<N>).»
       либо, при равенстве карт, «Партия пошла по кругу, карт поровну —
       дурака нет.»;
     - партияИзВида() (общее/js/сеть.js кладёт сюда ответ сервера) обязана
       передать флаг поКругу как есть — при его отсутствии считать false.

   Этот разработчик тексты не запускал: они читают экран (написать,
   показатьЭлемент) и глобальную переменную «партия» — без живого
   запуска ошибку там глазами не увидеть.

   Как проверяет. Поднимает НАСТОЯЩИЙ игры/дурак/game.js в песочнице vm (документ
   и узлы — из tests/поддельный-браузер.js), тем же приёмом, что и
   tests/выход-сдача-тексты.js: функции текстыИтога(), пояснениеКруга(),
   партияИзВида() читают и меняют глобальную «партия» верхнего уровня
   game.js — снаружи модуля (через require) её не увидеть, только через
   vm.runInContext в общем контексте со всем файлом.

   Запуск:
       node tests/дурак-круг-тексты.js            — обычный прогон
       node tests/дурак-круг-тексты.js --сломать  — берёт НЕ настоящий
         игры/дурак/game.js, а его испорченную КОПИЮ во временной папке (условие
         «партия.поКругу === true» в текстыИтога() заменено на false —
         пояснение про круг никогда не подставляется), и обязана
         покраснеть. Файл проекта эта проверка не трогает и не портит.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const vm = require('vm');
const { сделатьДокумент } = require('./поддельный-браузер');

const КОРЕНЬ = path.join(__dirname, '..');
const ФАЙЛ_ИГРЫ = path.join(КОРЕНЬ, 'игры', 'дурак', 'game.js');
const СЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;

/* Строка, которая подставляет пояснение круга в текстыИтога(). Именно её
   вырезает ломающий запуск. Не нашлась ровно один раз — это провал
   САМОЙ проверки (сигнатуру переименовали), а не тихий пропуск. */
const УСЛОВИЕ_КРУГА = /if \(партия && партия\.поКругу === true\) тексты\.пояснение = пояснениеКруга\(\);/g;

function путьКИгре() {
  if (!СЛОМАТЬ) return ФАЙЛ_ИГРЫ;
  const текст = fs.readFileSync(ФАЙЛ_ИГРЫ, 'utf8');
  const найдено = текст.match(УСЛОВИЕ_КРУГА) || [];
  if (найдено.length !== 1) {
    console.log('ПРОВАЛ: условие «поКругу» в текстыИтога() найдено ' + найдено.length +
      ' раз вместо одного — ломать нечего (проверку надо чинить)');
    console.log('Итого проверок: 1, провалов: 1');
    process.exit(1);
  }
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'дурак-круг-тексты-'));
  const копия = path.join(папка, 'game.js');
  fs.writeFileSync(копия, текст.replace(УСЛОВИЕ_КРУГА, 'if (false) тексты.пояснение = пояснениеКруга();'));
  console.log('Ломающий запуск: копия без вставки пояснения круга — ' + копия);
  return копия;
}

/**
 * document.getElementById, который на незнакомый id не возвращает null,
 * а честную пустышку — тот же приём, что в tests/выход-сдача-тексты.js.
 */
function позволитьЛюбыеId(документ) {
  const оригинал = документ.getElementById;
  const пустышки = new Map();
  документ.getElementById = function (id) {
    const найден = оригинал(id);
    if (найден) return найден;
    if (пустышки.has(id)) return пустышки.get(id);
    const узел = документ.createElement('div');
    узел.id = id;
    пустышки.set(id, узел);
    return узел;
  };
}

/** Поднять игры/дурак/game.js (или его испорченную копию) в песочнице vm. */
function поднятьИгру(путьGameJs) {
  const документ = сделатьДокумент();
  позволитьЛюбыеId(документ);

  const окно = {
    document: документ,
    addEventListener: function () {},
    removeEventListener: function () {},
    matchMedia: function () { return { matches: false, addEventListener: function () {}, addListener: function () {} }; },
    localStorage: { getItem: function () { return null; }, setItem: function () {}, removeItem: function () {} },
    innerWidth: 390, innerHeight: 844,
    requestAnimationFrame: function (ф) { return setTimeout(ф, 0); },
    cancelAnimationFrame: function (id) { clearTimeout(id); },
    getComputedStyle: function () {
      return { fontSize: '16px', lineHeight: '19.2px', getPropertyValue: function () { return ''; } };
    }
  };

  const песочница = {
    window: окно,
    document: документ,
    localStorage: окно.localStorage,
    navigator: { userAgent: 'тест дурак-круг-тексты' },
    console: { log: function () {}, info: function () {}, warn: function () {}, error: function () {} },
    setTimeout: setTimeout, clearTimeout: clearTimeout,
    setInterval: setInterval, clearInterval: clearInterval,
    Math: Math, Date: Date, JSON: JSON, Number: Number, String: String, Array: Array, Object: Object,
    Boolean: Boolean, RegExp: RegExp, Error: Error, isFinite: isFinite, isNaN: isNaN,
    parseInt: parseInt, parseFloat: parseFloat, Map: Map, Set: Set,
    requestAnimationFrame: окно.requestAnimationFrame,
    cancelAnimationFrame: окно.cancelAnimationFrame,
    getComputedStyle: окно.getComputedStyle
  };
  песочница.globalThis = песочница;
  vm.createContext(песочница);
  vm.runInContext(fs.readFileSync(путьGameJs, 'utf8'), песочница, { filename: путьGameJs + ' (дурак-круг-тексты)' });

  return {
    /** Прочитать выражение или вызвать функцию верхнего уровня game.js. */
    спросить: function (выражение) { return vm.runInContext(выражение, песочница); },
    /** Подставить объект «партия» целиком — тем же приёмом, что и подписьВыхода()
        в tests/выход-сдача-тексты.js: game.js читает эту переменную напрямую. */
    поставитьПартию: function (партия) {
      vm.runInContext('партия = ' + JSON.stringify(партия) + ';', песочница);
    }
  };
}

/** N фиктивных карт — их достоинство тут не важно, важно только число. */
function карты(сколько) {
  const ряд = [];
  for (let i = 0; i < сколько; i++) ряд.push({ масть: '♠', имя: '6', вес: 6 });
  return ряд;
}

/* =======================================================================
   ВЕСЬ НАБОР ПРОВЕРОК ОДНИМ ПРОГОНОМ
   ======================================================================= */
function прогнать(путьGameJs) {
  const строки = [];
  let провалов = 0;

  function проверить(имя, условие, подробности) {
    if (условие) {
      строки.push('OK    ' + имя);
    } else {
      провалов++;
      строки.push('ПЛОХО ' + имя + (подробности ? ' — ' + подробности : ''));
    }
  }

  let игра;
  try {
    игра = поднятьИгру(путьGameJs);
    проверить('0) игры/дурак/game.js поднимается в песочнице', true);
  } catch (сбой) {
    проверить('0) игры/дурак/game.js поднимается в песочнице', false, сбой.stack || сбой.message);
    return { строки: строки, провалов: провалов };
  }

  /* --- 1) Вдвоём, я выиграл по кругу --- */
  игра.поставитьПартию({
    результат: 'бот', проигравшие: ['бот'], завершена: true,
    поКругу: true, парами: false, ничья: false,
    руки: { человек: карты(2), бот: карты(5) }
  });
  const т1 = игра.спросить('текстыИтога()');
  проверить('1а) вдвоём, победа по кругу: заголовок обычный «Вы выиграли!»',
    т1 && т1.заголовок === 'Вы выиграли!', 'получено: ' + JSON.stringify(т1));
  проверить('1б) вдвоём, победа по кругу: пояснение называет «по кругу», имя дурака и число карт',
    т1 && т1.пояснение === 'Партия пошла по кругу — расклад повторился трижды. Дурак тот, у кого больше карт: соперник (5).',
    'получено: ' + JSON.stringify(т1 && т1.пояснение));

  /* --- 2) Вдвоём, я проиграл по кругу --- */
  игра.поставитьПартию({
    результат: 'человек', проигравшие: ['человек'], завершена: true,
    поКругу: true, парами: false, ничья: false,
    руки: { человек: карты(4), бот: карты(1) }
  });
  const т2 = игра.спросить('текстыИтога()');
  проверить('2а) вдвоём, поражение по кругу: заголовок обычный «Вы проиграли»',
    т2 && т2.заголовок === 'Вы проиграли', 'получено: ' + JSON.stringify(т2));
  проверить('2б) вдвоём, поражение по кругу: пояснение называет «по кругу» и моё имя «вы»',
    т2 && т2.пояснение === 'Партия пошла по кругу — расклад повторился трижды. Дурак тот, у кого больше карт: вы (4).',
    'получено: ' + JSON.stringify(т2 && т2.пояснение));

  /* --- 3) Ничья по кругу --- */
  игра.поставитьПартию({
    результат: 'ничья', проигравшие: [], завершена: true, ничья: true,
    поКругу: true, парами: false,
    руки: { человек: карты(3), бот: карты(3) }
  });
  const т3 = игра.спросить('текстыИтога()');
  проверить('3а) ничья по кругу: заголовок обычный «Ничья»',
    т3 && т3.заголовок === 'Ничья', 'получено: ' + JSON.stringify(т3));
  проверить('3б) ничья по кругу: пояснение «карт поровну — дурака нет»',
    т3 && т3.пояснение === 'Партия пошла по кругу, карт поровну — дурака нет.',
    'получено: ' + JSON.stringify(т3 && т3.пояснение));

  /* --- 4) Компания (трое+): один дурак по кругу --- */
  игра.поставитьПартию({
    результат: 'Бот 2', завершена: true, поКругу: true, парами: false,
    застолом: [
      { имя: 'Игрок 1', этоЯ: true, карт: 0, проиграл: false },
      { имя: 'Бот 2', этоЯ: false, карт: 5, проиграл: true },
      { имя: 'Бот 3', этоЯ: false, карт: 0, проиграл: false }
    ]
  });
  const т4 = игра.спросить('текстыИтога()');
  проверить('4а) компания, по кругу: заголовок обычный «Вы выиграли!» (я не дурак)',
    т4 && т4.заголовок === 'Вы выиграли!', 'получено: ' + JSON.stringify(т4));
  проверить('4б) компания, по кругу: пояснение называет «по кругу», имя дурака и число карт',
    т4 && т4.пояснение === 'Партия пошла по кругу — расклад повторился трижды. Дурак тот, у кого больше карт: Бот 2 (5).',
    'получено: ' + JSON.stringify(т4 && т4.пояснение));

  // Тот же стол, но дурак — я сам: пояснение должно назвать меня «вы».
  игра.поставитьПартию({
    результат: 'Игрок 1', завершена: true, поКругу: true, парами: false,
    застолом: [
      { имя: 'Игрок 1', этоЯ: true, карт: 6, проиграл: true },
      { имя: 'Бот 2', этоЯ: false, карт: 0, проиграл: false },
      { имя: 'Бот 3', этоЯ: false, карт: 0, проиграл: false }
    ]
  });
  const т4б = игра.спросить('текстыИтога()');
  проверить('4в) компания, по кругу, дурак я сам: заголовок обычный «Вы проиграли»',
    т4б && т4б.заголовок === 'Вы проиграли', 'получено: ' + JSON.stringify(т4б));
  проверить('4г) компания, по кругу, дурак я сам: пояснение называет меня «вы (6)»',
    т4б && т4б.пояснение === 'Партия пошла по кругу — расклад повторился трижды. Дурак тот, у кого больше карт: вы (6).',
    'получено: ' + JSON.stringify(т4б && т4б.пояснение));

  /* --- 5) Обычный конец без поКругу — тексты прежние, слов «по кругу» нет --- */
  игра.поставитьПартию({
    результат: 'бот', проигравшие: ['бот'], завершена: true,
    парами: false, ничья: false,
    руки: { человек: карты(0), бот: карты(3) }
    // поля «поКругу» нарочно нет — как у партии со старым сервером/обычным концом
  });
  const т5 = игра.спросить('текстыИтога()');
  проверить('5а) обычный конец: заголовок «Вы выиграли!» как всегда',
    т5 && т5.заголовок === 'Вы выиграли!', 'получено: ' + JSON.stringify(т5));
  проверить('5б) обычный конец: пояснение прежнее, слова «по кругу» в нём нет',
    // Внимание: перед тире в исходнике неразрывный пробел ( ), не обычный —
    // иначе сравнение молча проваливается даже на верном тексте.
    т5 && т5.пояснение === 'Соперник остался с картами — он и есть дурак.' &&
    т5.пояснение.indexOf('по кругу') === -1,
    'получено: ' + JSON.stringify(т5 && т5.пояснение));

  // И явное поКругу: false — тот же прежний текст.
  игра.поставитьПартию({
    результат: 'человек', проигравшие: ['человек'], завершена: true,
    поКругу: false, парами: false, ничья: false,
    руки: { человек: карты(3), бот: карты(0) }
  });
  const т5в = игра.спросить('текстыИтога()');
  проверить('5в) поКругу: false — пояснение прежнее, без «по кругу»',
    т5в && т5в.пояснение === 'Вы остались с картами — на этот раз дурак вы.' &&
    т5в.пояснение.indexOf('по кругу') === -1,
    'получено: ' + JSON.stringify(т5в && т5в.пояснение));

  /* --- 6) партияИзВида(): поКругу передаётся честно --- */
  const видБазовый = {
    завершена: true, итог: 'победа',
    соперникПришёл: true, соперникНаСвязи: true,
    мояРука: [], картУСоперника: 0,
    стол: [], козырь: '♠', козырнаяКарта: { масть: '♠', имя: '6', вес: 6 },
    вКолоде: 0, вОтбое: 30, подходов: 5,
    яХожу: false, яАтакую: false,
    берут: false, могуПодкинуть: false, могуПеревести: false, могуПодхватить: false,
    номерСобытия: 1
  };
  const видСПолем = Object.assign({}, видБазовый, { поКругу: true });
  const партияСПоля = игра.спросить('партияИзВида(' + JSON.stringify(видСПолем) + ')');
  проверить('6а) партияИзВида: вид.поКругу === true → партия.поКругу === true',
    партияСПоля && партияСПоля.поКругу === true,
    'получено: ' + JSON.stringify(партияСПоля && партияСПоля.поКругу));

  const партияБезПоля = игра.спросить('партияИзВида(' + JSON.stringify(видБазовый) + ')');
  проверить('6б) партияИзВида: поля «поКругу» в ответе сервера нет → партия.поКругу === false',
    партияБезПоля && партияБезПоля.поКругу === false,
    'получено: ' + JSON.stringify(партияБезПоля && партияБезПоля.поКругу));

  return { строки: строки, провалов: провалов };
}

console.log('=== Тексты итога по кругу в игре (файл: ' + (СЛОМАТЬ ? '(будет испорченная копия ниже)' : ФАЙЛ_ИГРЫ) + ') ===\n');
const путь = путьКИгре();
const { строки, провалов } = прогнать(путь);
строки.forEach(function (с) { console.log(с); });
console.log('');
console.log('Итого проверок: ' + строки.length + ', провалов: ' + провалов);
process.exitCode = провалов ? 1 : 0;
