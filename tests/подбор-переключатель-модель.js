/**
 * Игрок нажал «Отменить» ПОСЛЕ того, как первый /подбор уже улетел на
 * сервер, но ДО того, как пришёл ответ. Сервер успел поставить нас
 * в очередь («ждёт» + ключОжидания) — ответ приходит, когда поколение
 * подбора на клиенте уже другое. Такой ответ не должен повиснуть молча:
 * клиент обязан сам сходить в /подбор-отмена тем же ключом.
 */
async function проверитьПризракЖдёт(исходник) {
  console.log('\n=== Г1. Призрак «ждёт» после отмены: закрываем тихим /подбор-отмена ===');
  const запросы = [];
  const { Сеть, ждущие } = поднятьСетьОтложенно(исходник, запросы);

  const итог = Сеть.встатьВОчередь({ переводной: true });   // первый /подбор — без await
  await подождать();   // дать запросу дойти до fetch — сам ответ пока висит
  проверить(ждущие.length === 1 && ждущие[0].путь === '/подбор',
    'первый /подбор ушёл и висит (получили ' + JSON.stringify(ждущие.map(function (з) { return з.путь; })) + ')');

  Сеть.отменитьПодбор();   // «Отменить» — раньше, чем сервер ответил на первый /подбор

  ждущие[0].отдать({ статус: 'ждёт', ключОжидания: 'к1', доБота: 20000 });   // сервер поставил в очередь уже после отмены
  const встал = await итог;
  проверить(встал && встал.статус === 'ошибка',
    'ответ на уже отменённый /подбор не встаёт молча в очередь (получили ' + JSON.stringify(встал) + ')');

  await подождать();
  const отмена = запросы.filter(function (з) { return з.путь === '/подбор-отмена'; })[0];
  проверить(Boolean(отмена) && отмена.тело && отмена.тело.ключОжидания === 'к1',
    'призрак закрыт: /подбор-отмена ушёл с ключом «к1» (запросы: ' + JSON.stringify(запросы) + ')');
}

/**
 * То же самое, но сервер успел не просто поставить в очередь, а сразу
 * СВЕСТИ с соперником — ответ «свели» приходит, когда поколение уже
 * другое. Комнату на сервере создали по-настоящему, и клиент обязан
 * её покинуть тем же путём, что обычный выход (/выйти), а не оставить
 * соперника сидеть напротив пустого места.
 */
async function проверитьПризракСвели(исходник) {
  console.log('\n=== Г2. Призрак «свели» после отмены: закрываем тихим /выйти ===');
  const запросы = [];
  const { Сеть, ждущие } = поднятьСетьОтложенно(исходник, запросы);

  const итог = Сеть.встатьВОчередь({ переводной: true });
  await подождать();
  проверить(ждущие.length === 1 && ждущие[0].путь === '/подбор',
    'первый /подбор ушёл и висит (получили ' + JSON.stringify(ждущие.map(function (з) { return з.путь; })) + ')');

  Сеть.отменитьПодбор();

  ждущие[0].отдать({ статус: 'свели', код: 'ФФФФ', пропуск: 'ппп', состояние: {} });
  const встал = await итог;
  проверить(встал && встал.статус === 'ошибка',
    'ответ «свели» на уже отменённый /подбор не открывает комнату молча (получили ' + JSON.stringify(встал) + ')');

  await подождать();
  const выход = запросы.filter(function (з) { return з.путь === '/выйти'; })[0];
  проверить(Boolean(выход) && выход.тело && выход.тело.код === 'ФФФФ' && выход.тело.пропуск === 'ппп',
    'призрак закрыт: /выйти ушёл с кодом «ФФФФ» и пропуском «ппп» (запросы: ' + JSON.stringify(запросы) + ')');
}

/**
 * Опоздавший «призрак» — не всегда чужая комната. Игрок жмёт «Отменить»,
 * пока первый /подбор ещё висит без ответа, сразу жмёт «Играть онлайн»
 * снова — второй /подбор сажает за стол по-настоящему. Сервер 60 секунд
 * помнит посадку по паре «человек + игра» (см. «повторПодбораБыл»
 * в js/сеть.js) — и опоздавший ответ на ПЕРВЫЙ запрос приходит с тем же
 * кодом и пропуском, что уже открыты вторым. Это не призрак, а живая
 * комната, в которой игрок уже сидит: тихий /выйти по этому ответу
 * выбросил бы его из собственной партии (нашёл ревьюер).
 */
async function проверитьЖивуюКомнату(исходник) {
  console.log('\n=== Г3. Опоздавший «свели» с кодом ЖИВОЙ комнаты — /выйти не шлём ===');
  const запросы = [];
  const { Сеть, ждущие } = поднятьСетьОтложенно(исходник, запросы);

  const итог1 = Сеть.встатьВОчередь({ переводной: true });   // первый /подбор — висит без ответа
  await подождать();
  проверить(ждущие.length === 1 && ждущие[0].путь === '/подбор',
    'первый /подбор ушёл и висит (получили ' + JSON.stringify(ждущие.map(function (з) { return з.путь; })) + ')');

  Сеть.отменитьПодбор();   // «Отменить» — первый ответ ещё не пришёл

  const итог2 = Сеть.встатьВОчередь({ переводной: true });   // тут же «Играть онлайн» снова
  await подождать();
  проверить(ждущие.length === 2 && ждущие[1].путь === '/подбор',
    'второй /подбор тоже ушёл и висит (получили ' + JSON.stringify(ждущие.map(function (з) { return з.путь; })) + ')');

  ждущие[1].отдать({ статус: 'свели', код: 'X', пропуск: 'п-X', состояние: {} });   // второй сажает за стол
  const встал2 = await итог2;
  проверить(встал2 && встал2.статус === 'свели', 'второй /подбор реально свёл (получили ' + JSON.stringify(встал2) + ')');

  ждущие[0].отдать({ статус: 'свели', код: 'X', пропуск: 'п-X', состояние: {} });   // опоздавший первый — тот же стол
  const встал1 = await итог1;
  проверить(встал1 && встал1.статус === 'ошибка',
    'опоздавший первый ответ не встаёт молча в очередь (получили ' + JSON.stringify(встал1) + ')');

  await подождать();
  const выход = запросы.filter(function (з) { return з.путь === '/выйти'; })[0];
  проверить(!выход, 'живую комнату /выйти не покидает (запросы: ' + JSON.stringify(запросы) + ')');

  // Игрок и правда остался в комнате X: ближайший ход уходит с её кодом
  // и пропуском (единственный способ снаружи убедиться, что комната жива).
  // Без await: этот fetch в поднятьСетьОтложенно ничего не отвечает —
  // достаточно, что тело запроса уже ушло синхронно.
  Сеть.отправитьХод({});
  await подождать();
  const ход = запросы.filter(function (з) { return з.путь === '/ход'; }).pop();
  проверить(Boolean(ход) && ход.тело && ход.тело.код === 'X' && ход.тело.пропуск === 'п-X',
    'игрок остался в комнате X: ход ушёл с её кодом и пропуском (запросы: ' + JSON.stringify(запросы) + ')');
}

/**
 * Общее начало Г4–Г6: первый /подбор висит, «Отменить», тут же второй
 * /подбор — и опоздавший ответ ПЕРВОГО («свели» в стол X) приходит
 * раньше ответа второго. Возвращает всё, что нужно для продолжения.
 */
async function обогналОпоздавший(исходник) {
  const запросы = [];
  const { Сеть, ждущие } = поднятьСетьОтложенно(исходник, запросы);

  const итог1 = Сеть.встатьВОчередь({ переводной: true });
  await подождать();
  Сеть.отменитьПодбор();
  const итог2 = Сеть.встатьВОчередь({ переводной: true });
  await подождать();
  проверить(ждущие.length === 2 && ждущие[0].путь === '/подбор' && ждущие[1].путь === '/подбор',
    'оба /подбор ушли и висят (получили ' + JSON.stringify(ждущие.map(function (з) { return з.путь; })) + ')');

  ждущие[0].отдать({ статус: 'свели', код: 'X', пропуск: 'п-X', состояние: {} });   // опоздавший — ПЕРВЫМ
  const встал1 = await итог1;
  await подождать();
  проверить(встал1 && встал1.статус === 'ошибка',
    'опоздавший первый ответ не открывает комнату (получили ' + JSON.stringify(встал1) + ')');
  проверить(сколько(запросы, '/выйти') === 0,
    'пока повтор не ответил, /выйти не ушёл — решение отложено (запросы: ' + JSON.stringify(запросы) + ')');
  return { Сеть: Сеть, ждущие: ждущие, запросы: запросы, итог2: итог2 };
}

function последнийХод(запросы) {
  return запросы.filter(function (з) { return з.путь === '/ход'; }).pop();
}

/** Г4: повтор вернул тот же стол X — выходить нельзя, ход уходит в X. */
async function проверитьОбратныйПорядокТотЖеСтол(исходник) {
  console.log('\n=== Г4. Обратный порядок, повтор вернул тот же стол — /выйти не шлём ===');
  const { Сеть, ждущие, запросы, итог2 } = await обогналОпоздавший(исходник);

  ждущие[1].отдать({ статус: 'свели', код: 'X', пропуск: 'п-X', состояние: {} });
  const встал2 = await итог2;
  await подождать();
  проверить(встал2 && встал2.статус === 'свели', 'повтор свёл (получили ' + JSON.stringify(встал2) + ')');
  проверить(сколько(запросы, '/выйти') === 0,
    'из живого стола X /выйти не ушёл (запросы: ' + JSON.stringify(запросы) + ')');

  Сеть.отправитьХод({});
  await подождать();
  const ход = последнийХод(запросы);
  проверить(Boolean(ход) && ход.тело && ход.тело.код === 'X' && ход.тело.пропуск === 'п-X',
    'игрок в столе X: ход ушёл с его кодом и пропуском (запросы: ' + JSON.stringify(запросы) + ')');
}

/** Г5: повтор вернул ДРУГОЙ стол Y — отложенный /выйти по X обязан уйти. */
async function проверитьОбратныйПорядокДругойСтол(исходник) {
  console.log('\n=== Г5. Обратный порядок, повтор вернул другой стол — отложенный /выйти по старому ===');
  const { Сеть, ждущие, запросы, итог2 } = await обогналОпоздавший(исходник);

  ждущие[1].отдать({ статус: 'свели', код: 'Y', пропуск: 'п-Y', состояние: {} });
  const встал2 = await итог2;
  await подождать();
  проверить(встал2 && встал2.статус === 'свели', 'повтор свёл в Y (получили ' + JSON.stringify(встал2) + ')');
  const выходы = запросы.filter(function (з) { return з.путь === '/выйти'; });
  проверить(выходы.length === 1 && выходы[0].тело.код === 'X' && выходы[0].тело.пропуск === 'п-X',
    'ушёл ровно один /выйти — по старому столу X (запросы: ' + JSON.stringify(запросы) + ')');

  Сеть.отправитьХод({});
  await подождать();
  const ход = последнийХод(запросы);
  проверить(Boolean(ход) && ход.тело && ход.тело.код === 'Y',
    'игрок в столе Y: ход ушёл с его кодом (запросы: ' + JSON.stringify(запросы) + ')');
}

/**
 * Г6: обратный порядок, а потом игрок жмёт «Отменить» ещё раз, пока повтор
 * висит. Повтор отвечает уже устаревшим «свели» в тот же X — отложенный
 * выход не теряется: /выйти по X уходит, и ровно один раз.
 */
async function проверитьОбратныйПорядокПовторнаяОтмена(исходник) {
  console.log('\n=== Г6. Обратный порядок и повторная «Отменить» — отложенный /выйти не теряется ===');
  const { Сеть, ждущие, запросы, итог2 } = await обогналОпоздавший(исходник);

  Сеть.отменитьПодбор();
  ждущие[1].отдать({ статус: 'свели', код: 'X', пропуск: 'п-X', состояние: {} });
  const встал2 = await итог2;
  await подождать();
  проверить(встал2 && встал2.статус === 'ошибка',
    'отменённый повтор не открывает комнату (получили ' + JSON.stringify(встал2) + ')');
  const выходы = запросы.filter(function (з) { return з.путь === '/выйти'; });
  проверить(выходы.length === 1 && выходы[0].тело.код === 'X',
    'ушёл ровно один /выйти по X (запросы: ' + JSON.stringify(запросы) + ')');
}

/* ---------------------------------------------------------------------
   Главное
   --------------------------------------------------------------------- */

async function главное() {
  let копииПапка = null;
  let путьКомнаты = довод('комната');
  let путьСети = довод('сеть');

  let ломать;
  try {
    ломать = аргСломать();
  } catch (сбой) {
    console.error(String(сбой && сбой.message || сбой));
    process.exit(2);
    return;
  }

  // Папку заводим и портим копию уже внутри try/finally: упади приготовление
  // ломающей копии на середине — временная папка всё равно должна убраться,
  // а не остаться мусором на диске.
  try {
    if (ломать) {
      копииПапка = fs.mkdtempSync(path.join(os.tmpdir(), 'подбор-переключатель-сломать-' + ломать + '-'));
      if (ломать === 'комната' && !путьКомнаты) путьКомнаты = приготовитьЛомающуюКомнату(копииПапка);
      if (ломать === 'сеть' && !путьСети) путьСети = приготовитьЛомающуюСетьПовтор(копииПапка);
      if (ломать === 'призрак' && !путьСети) путьСети = приготовитьЛомающуюСетьПризрак(копииПапка);
      if (ломать === 'живая-комната' && !путьСети) путьСети = приготовитьЛомающуюСетьЖиваяКомната(копииПапка);
      if (ломать === 'обратный-порядок' && !путьСети) путьСети = приготовитьЛомающуюСетьОбратныйПорядок(копииПапка);
      console.log('*** ЛОМАЮЩИЙ ЗАПУСК (' + ломать + '): копия во временной папке ' +
        копииПапка + ' — эта проверка обязана покраснеть. ***');
    }

    путьКомнаты = путьКомнаты || path.join(КОРЕНЬ, 'js', 'дурак-комната.js');
    путьСети = путьСети || path.join(КОРЕНЬ, 'js', 'сеть.js');
    console.log('  дурак-комната.js: ' + путьКомнаты);
    console.log('  сеть.js: ' + путьСети);

    const исходникКомнаты = fs.readFileSync(путьКомнаты, 'utf8');
    const исходникСети = fs.readFileSync(путьСети, 'utf8');
    const ДуракКомната = require(путьКомнаты);
    проверитьМодель(ДуракКомната);
    await проверитьСтраницу(исходникКомнаты);
    await проверитьПовтор(исходникСети);
    await проверитьПризракЖдёт(исходникСети);
    await проверитьПризракСвели(исходникСети);
    await проверитьЖивуюКомнату(исходникСети);
    await проверитьОбратныйПорядокТотЖеСтол(исходникСети);
    await проверитьОбратныйПорядокДругойСтол(исходникСети);
    await проверитьОбратныйПорядокПовторнаяОтмена(исходникСети);
  } catch (сбой) {
    проверить(false, 'проверка упала — ' + (сбой && сбой.stack || сбой));
  } finally {
    if (копииПапка) {
      try { fs.rmSync(копииПапка, { recursive: true, force: true }); } catch (сбой) { /* не страшно */ }
    }
  }

  const провалы = проверки.filter(function (п) { return !п.ок; });
  console.log('\nИтого проверок: ' + проверки.length + ', провалов: ' + провалы.length);
  process.exit(провалы.length || проверки.length === 0 ? 1 : 0);
}

главное();
