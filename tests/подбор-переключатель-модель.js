/* ---------------------------------------------------------------------
   Ломающие копии — во временной папке ОС, файлы проекта не трогаем.
   Каждая портит РОВНО ОДИН файл — другой при этом остаётся настоящим,
   чтобы было видно, какая проверка на что среагировала.
   --------------------------------------------------------------------- */
function заменитьИлиУпасть(текст, что, наЧто, файл) {
  if (текст.indexOf(что) === -1) {
    throw new Error('не нашёл в ' + файл + ' строку «' + что + '» — ломающий приём устарел, поправь его');
  }
  return текст.replace(что, наЧто);
}

