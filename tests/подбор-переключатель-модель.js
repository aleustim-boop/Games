function довод(имя) {
  const найден = process.argv.find(function (д) { return д.indexOf('--' + имя + '=') === 0; });
  return найден ? найден.slice(имя.length + 3) : '';
}

/** --сломать=комната|сеть|призрак|живая-комната|обратный-порядок — значение обязательно, иначе неясно, что ломаем. */
function аргСломать() {
  const флаг = process.argv.find(function (а) { return а === '--сломать' || а.indexOf('--сломать=') === 0; });
  if (!флаг) return null;
  const значение = флаг.indexOf('=') === -1 ? '' : флаг.slice(флаг.indexOf('=') + 1);
  if (['комната', 'сеть', 'призрак', 'живая-комната', 'обратный-порядок'].indexOf(значение) === -1) {
    throw new Error('нужно указать --сломать=комната, --сломать=сеть, --сломать=призрак, --сломать=живая-комната или --сломать=обратный-порядок (получили «' + значение + '»)');
  }
  return значение;
}

