/** id строки подбора и её подписи — из index.html, второй копии не заводим. */
function узлыСтрокиИзРазметки() {
  const разметка = fs.readFileSync(path.join(КОРЕНЬ, 'index.html'), 'utf8');
  const строка = разметка.match(/<button id="(комната-подбор)"[^>]*class="комната__подбор"[^>]*>\s*<span id="([^"]+)"><\/span>\s*<span class="(комната__скоро)">/);
  if (!строка) throw new Error('в index.html не нашёл строку подбора (кнопка + подпись + пометка) — проверка устарела');
  return { кнопка: строка[1], подпись: строка[2], пометка: строка[3] };
}

function построитьСтраницу(исходник, ид) {
  const документ = сделатьДокумент();
  const корень = документ.узел('div', { id: 'комната' });
  const кнопка = документ.узел('button', { id: ид.кнопка, класс: 'комната__подбор' },
    документ.узел('span', { id: ид.подпись }),
    документ.узел('span', { класс: ид.пометка, текст: 'скоро' }));
  кнопка.disabled = true;
  корень.appendChild(кнопка);
  документ.body.appendChild(корень);
  const рез = поднять(исходник, { документ: документ, имяФайла: 'js/дурак-комната.js' });
  return { окно: рез.окно, документ: документ, кнопка: кнопка };
}

async function проверитьСтраницу(исходник) {
  console.log('\n=== Б. Страница: строка подбора в поддельном DOM ===');
  const ид = узлыСтрокиИзРазметки();

  // Хозяин, стол открыт: включён, нажатие закрывает.
  {
    const с = построитьСтраницу(исходник, ид);
    const вызовы = [];
    const двери = {
      действие: function (имя, поля) {
        вызовы.push({ имя: имя, поля: поля });
        return Promise.resolve({ принято: true, состояние: видКомпании({ открытыйСтол: !(поля && поля.открыть === false) }) });
      }
    };
    с.окно.ДуракКомната.показать(видКомпании(), двери);
    проверить(с.кнопка.getAttribute('aria-checked') === 'true', 'хозяин, открыт: aria-checked="true"');
    проверить(с.кнопка.disabled === false, 'хозяин, открыт: кнопку можно нажать');
    проверить(!с.кнопка.classList.contains('скрыт'), 'хозяин, открыт: строка видна');
    const пометка = с.кнопка.querySelector('.' + ид.пометка);
    проверить(пометка && пометка.classList.contains('скрыт'), 'хозяин: пометка «скоро» спрятана');
    с.кнопка.click();
    await подождать();
    проверить(вызовы.length === 1 && вызовы[0].имя === 'открыть-стол' && вызовы[0].поля.открыть === false,
      'хозяин нажал на открытом: ушло «открыть-стол» с открыть=false (ушло ' + JSON.stringify(вызовы) + ')');
    проверить(с.кнопка.getAttribute('aria-checked') === 'false', 'после ответа сервера переключатель выключен');
    с.кнопка.click();
    await подождать();
    проверить(вызовы.length === 2 && вызовы[1].поля.открыть === true,
      'хозяин нажал снова: ушло открыть=true');
    с.окно.ДуракКомната.спрятать();
  }

  // Не хозяин: видит положение, нажатие не шлёт ничего.
  {
    const с = построитьСтраницу(исходник, ид);
    const вызовы = [];
    const двери = { действие: function (имя, поля) { вызовы.push(имя); return Promise.resolve({ принято: true }); } };
    с.окно.ДуракКомната.показать(видКомпании({ яХозяин: false }), двери);
    проверить(с.кнопка.getAttribute('aria-checked') === 'true', 'не хозяин, открыт: aria-checked="true"');
    проверить(с.кнопка.disabled === true, 'не хозяин: кнопка недоступна');
    const пометка = с.кнопка.querySelector('.' + ид.пометка);
    проверить(пометка && !пометка.classList.contains('скрыт') && пометка.textContent === с.окно.ДуракКомната.СЛОВА.подборУХозяина,
      'не хозяин: пометка говорит, что включает хозяин');
    с.кнопка.click();
    await подождать();
    проверить(вызовы.length === 0, 'не хозяин нажал: серверу ничего не ушло');
    с.окно.ДуракКомната.спрятать();
  }

  // Домино: строки нет.
  {
    const с = построитьСтраницу(исходник, ид);
    с.окно.ДуракКомната.показать(видКомпании({ игра: 'домино' }), { действие: function () { return Promise.resolve({}); } });
    проверить(с.кнопка.classList.contains('скрыт'), 'домино: строка подбора спрятана');
    с.окно.ДуракКомната.спрятать();
  }

  // Стол не на двоих (например «парами» на четверых), открыт — переключатель
  // включён и хозяин может его нажать (главное отличие этого этапа).
  {
    const с = построитьСтраницу(исходник, ид);
    const вызовы = [];
    const двери = {
      действие: function (имя, поля) {
        вызовы.push({ имя: имя, поля: поля });
        return Promise.resolve({ принято: true, состояние: видКомпании({ мест: 4, парами: true, открытыйСтол: !(поля && поля.открыть === false) }) });
      }
    };
    с.окно.ДуракКомната.показать(видКомпании({ мест: 4, парами: true }), двери);
    проверить(с.кнопка.getAttribute('aria-checked') === 'true', 'парами на четверых, открыт: aria-checked="true"');
    проверить(с.кнопка.disabled === false, 'парами на четверых, открыт: кнопку можно нажать');
    проверить(!с.кнопка.classList.contains('скрыт'), 'парами на четверых, открыт: строка видна');
    с.кнопка.click();
    await подождать();
    проверить(вызовы.length === 1 && вызовы[0].поля.открыть === false,
      'парами на четверых: нажатие хозяина ушло с открыть=false (ушло ' + JSON.stringify(вызовы) + ')');
    с.окно.ДуракКомната.спрятать();
  }

  // Двойное нажатие подряд, ДО await, пока ответ дверей висит:
  // серверу должен уйти ровно один запрос (защита от повторного клика).
  {
    const с = построитьСтраницу(исходник, ид);
    const вызовы = [];
    let отдать = null;
    const двери = {
      действие: function (имя, поля) {
        вызовы.push({ имя: имя, поля: поля });
        return new Promise(function (готово) { отдать = готово; });   // висит, пока сами не отдадим
      }
    };
    с.окно.ДуракКомната.показать(видКомпании(), двери);
    с.кнопка.click();
    с.кнопка.click();   // второй клик — раньше первого await, флаг «ждёмОтвета» блокирует его синхронно
    // Само двери.действие() вызывается из выполнитьНамерения() внутри .then(),
    // то есть микрозадачей — дать ей отработать, прежде чем считать вызовы.
    await Promise.resolve();
    await Promise.resolve();
    проверить(вызовы.length === 1, 'двойной клик до ответа дверей: ушёл один запрос (ушло ' + вызовы.length + ')');
    проверить(typeof отдать === 'function', 'дверям правда есть что отдавать (запрос реально ушёл)');
    отдать({ принято: true, состояние: видКомпании({ открытыйСтол: false }) });
    await подождать();
    проверить(вызовы.length === 1, 'после ответа второй клик так и не ушёл (ушло ' + вызовы.length + ')');
    с.окно.ДуракКомната.спрятать();
  }
}

