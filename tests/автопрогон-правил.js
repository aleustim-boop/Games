/* =====================================================================
   Автопрогон правил «Подкидного дурака» — независимая проверка тестировщика.

   Что делает: играет много партий сама с собой (без браузера) и после
   КАЖДОГО хода проверяет, что правила не нарушены и карты не потерялись.

   Два разных игрока:
     1) «жадный» — штатный бот из js/game.js (как в игре);
     2) «случайный» — ходит любым разрешённым способом наугад.
        Он нужен, чтобы залезть в те положения, до которых жадный бот
        никогда не доходит (например, подкидывает козыри или берёт,
        хотя мог отбиться).

   Запуск:  node tests/автопрогон-правил.js [сколько партий каждым игроком]
   ===================================================================== */

