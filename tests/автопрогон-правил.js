const путьКИгре = require('path').join(__dirname, '..', 'js', 'game.js');
const игра = require(путьКИгре);

const ПАРТИЙ = Number(process.argv[2]) || 600;   // столько партий каждым из двух игроков
const ПРЕДЕЛ_ХОДОВ = 400;                        // больше — считаем, что партия зависла

/* Повторимая случайность: тот же номер партии — та же раздача.
   Генератор общий на все проверки и лежит отдельно (tests/общий-генератор.js).
   Прежняя самодельная копия теряла младшие разряды при умножении: она ходила
   по кругу всего из 11-16 тысяч чисел, а бросок «выбери одно из 36» был перекошен
   на треть. Из-за замены НОМЕРА ПАРТИЙ ИЗ ОТЧЁТОВ, СДЕЛАННЫХ РАНЬШЕ, больше
   не воспроизводятся: под тем же номером теперь другая раздача. */
const генератор = require(require('path').join(__dirname, 'общий-генератор.js'));
генератор.захватитьСлучайность();
генератор.поставитьЗерно(1);

/* ---------------------------------------------------------------------
   Вспомогательное
   --------------------------------------------------------------------- */

function имяКарты(карта) {
  return карта.имя + карта.масть;
}

/** Все карты партии, где бы они ни лежали. */
function всеКарты(партия) {
  const список = [];
  for (const к of партия.колода) список.push(к);
  for (const к of партия.руки.человек) список.push(к);
  for (const к of партия.руки.бот) список.push(к);
  for (const к of партия.отбой) список.push(к);
  for (const пара of партия.стол) {
    список.push(пара.атака);
    if (пара.защита) список.push(пара.защита);
  }
  return список;
}

/** Достоинства, лежащие на столе прямо сейчас. */
function достоинстваСтола(партия) {
  const набор = new Set();
  for (const пара of партия.стол) {
    набор.add(пара.атака.имя);
    if (пара.защита) набор.add(пара.защита.имя);
  }
  return набор;
}

/** Короткий снимок стола — чтобы сравнить «до хода» и «после хода». */
function снимокСтола(партия) {
  return партия.стол.map(function (пара) {
    return { атака: имяКарты(пара.атака), защита: пара.защита ? имяКарты(пара.защита) : null };
  });
}

/* ---------------------------------------------------------------------
   Проверки состояния. Каждая возвращает текст ошибки или null.
   --------------------------------------------------------------------- */

const ПОЛНАЯ_КОЛОДА = игра.собратьКолоду().map(имяКарты).sort();

function проверитьСостояние(партия) {
  const беды = [];

  // 1. Все 36 карт на месте, ничего не пропало и не размножилось.
  const карты = всеКарты(партия);
  if (карты.length !== 36) {
    беды.push('карт в партии ' + карты.length + ' вместо 36');
  }
  const поИмени = карты.map(имяКарты).sort();
  for (let i = 0; i < Math.max(поИмени.length, ПОЛНАЯ_КОЛОДА.length); i++) {
    if (поИмени[i] !== ПОЛНАЯ_КОЛОДА[i]) {
      беды.push('набор карт испортился: ожидалось ' + ПОЛНАЯ_КОЛОДА[i] + ', лежит ' + поИмени[i]);
      break;
    }
  }
  // Одна и та же карта не может лежать в двух местах сразу.
  const ссылки = new Set();
  for (const к of карты) {
    if (ссылки.has(к)) беды.push('карта ' + имяКарты(к) + ' лежит сразу в двух местах');
    ссылки.add(к);
  }

  // 2. На столе не больше шести пар.
  if (партия.стол.length > 6) {
    беды.push('на столе ' + партия.стол.length + ' карт — больше шести');
  }

  // 3. Каждая побитая карта побита по правилам.
  for (const пара of партия.стол) {
    if (пара.защита && !игра.бьёт(пара.защита, пара.атака, партия.козырь)) {
      беды.push('карта ' + имяКарты(пара.атака) + ' побита неподходящей картой ' +
        имяКарты(пара.защита) + ' (козырь ' + партия.козырь + ')');
    }
  }

  // 4. Козырная карта лежит последней в колоде, пока колода не пуста.
  if (партия.колода.length > 0 && партия.колода[партия.колода.length - 1] !== партия.козырнаяКарта) {
    беды.push('козырная карта не лежит под колодой');
  }

  // 5. Пока в колоде есть карты, начинать новый заход можно только
  //    с полными руками по шесть карт (значит, добор работает).
  if (!партия.завершена && партия.колода.length > 0 && партия.стол.length === 0) {
    if (партия.руки.человек.length < 6 || партия.руки.бот.length < 6) {
      беды.push('колода не пуста (' + партия.колода.length + '), а руки недобраны: человек ' +
        партия.руки.человек.length + ', бот ' + партия.руки.бот.length);
    }
  }

  // 6. Пока партия не окончена, кто-то обязан ходить.
  if (!партия.завершена && игра.ктоХодит(партия) === null) {
    беды.push('партия не окончена, а ходить некому — это зависание');
  }

  // 7. Если партия окончена — проверяем, что проигравший определён верно.
  if (партия.завершена) {
    const человекПуст = партия.руки.человек.length === 0;
    const ботПуст = партия.руки.бот.length === 0;
    if (партия.колода.length > 0) беды.push('партия окончена, а в колоде ещё ' + партия.колода.length + ' карт');
    if (партия.стол.length > 0) беды.push('партия окончена, а на столе остались карты');
    let ожидаемый;
    if (человекПуст && ботПуст) ожидаемый = 'ничья';
    else if (человекПуст) ожидаемый = 'бот';
    else if (ботПуст) ожидаемый = 'человек';
    else ожидаемый = 'никто (у обоих есть карты)';
    if (партия.результат !== ожидаемый) {
      беды.push('проигравший определён неверно: записано «' + партия.результат +
        '», а по рукам выходит «' + ожидаемый + '» (человек ' + партия.руки.человек.length +
        ' карт, бот ' + партия.руки.бот.length + ')');
    }
  }

  return беды;
}

/**
 * Сверяем стол до хода и после: не появилась ли карта чужого достоинства.
 */
function проверитьПодкидывание(доСнимок, доДостоинства, партия) {
  const беды = [];
  const после = снимокСтола(партия);
  // Стол только пополнился (иначе заход закончился — сравнивать нечего).
  if (после.length <= доСнимок.length) return беды;
  for (let i = доСнимок.length; i < после.length; i++) {
    if (доСнимок.length === 0 && i === 0) continue; // первая карта захода — любая
    const достоинство = после[i].атака.slice(0, -1);
    if (!доДостоинства.has(достоинство)) {
      беды.push('подкинута карта ' + после[i].атака + ' чужого достоинства: на столе были только ' +
        Array.from(доДостоинства).join(', '));
    }
  }
  return беды;
}

