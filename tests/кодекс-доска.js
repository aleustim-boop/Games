async function прогон(программа, настройки) {
  const н = Object.assign({ тихо: false, гонка: true }, настройки);
  const у = новыйУчёт(н.тихо);
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'кодекс-проба-'));
  const корень = path.join(tmp, 'корень');
  fs.mkdirSync(path.join(корень, 'img', 'проба'), { recursive: true });
  fs.mkdirSync(path.join(корень, 'img', 'другая'), { recursive: true });
  const ср = { программа, tmp, корень, доска: path.join(tmp, 'доска.json') };
  fs.writeFileSync(ср.доска, '{\n  "задачи": []\n}\n', 'utf8');
  try {
    проверкаRequire(у, ср);
    проверкаКруга(у, ср);
    проверкаКартинок(у, ср);
    проверкаСдачиОтказы(у, ср);
    проверкаПереходов(у, ср);
    проверкаДобавитьОтказы(у, ср);
    проверкаПереписать(у, ср);
    проверкаПрочихОтказов(у, ср);
    if (н.гонка) await проверкаГонки(у, ср);
  } catch (е) {
    проверь(у, 'проверка не должна падать сама', false, е && е.stack);
  }
  if (!process.argv.includes('--оставить')) {
    try {
      if (tmp.startsWith(os.tmpdir()) && path.basename(tmp).startsWith('кодекс-проба-')) fs.rmSync(tmp, { recursive: true, force: true });
    } catch (е) {}
  } else {
    у.заметки.push('Временная папка оставлена: ' + tmp);
  }
  return у;
}

