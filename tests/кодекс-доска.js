const ПОДПИСЬ_PNG = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
const ТАБЛИЦА_CRC = (() => {
  const т = [];
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    т.push(c >>> 0);
  }
  return т;
})();

function crc32(б) {
  let c = 0xffffffff;
  for (const x of б) c = ТАБЛИЦА_CRC[(c ^ x) & 255] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function блокPng(тип, данные) {
  const длина = Buffer.alloc(4);
  длина.writeUInt32BE(данные.length);
  const т = Buffer.from(тип, 'latin1');
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(Buffer.concat([т, данные])));
  return Buffer.concat([длина, т, данные, crc]);
}

// Настоящий png: подпись, IHDR, IDAT (сжатые через zlib чёрные точки), IEND.
function png(ш, в) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(ш, 0);
  ihdr.writeUInt32BE(в, 4);
  ihdr[8] = 8; // глубина
  ihdr[9] = 2; // цвет RGB
  const сырое = Buffer.alloc(в * (1 + ш * 3));
  return Buffer.concat([ПОДПИСЬ_PNG, блокPng('IHDR', ihdr), блокPng('IDAT', zlib.deflateSync(сырое)), блокPng('IEND', Buffer.alloc(0))]);
}

function чанкWebp(имя, данные) {
  const з = Buffer.alloc(8);
  з.write(имя, 0, 'latin1');
  з.writeUInt32LE(данные.length, 4);
  const пад = данные.length % 2 ? Buffer.alloc(1) : Buffer.alloc(0);
  return Buffer.concat([з, данные, пад]);
}

function riff(куски) {
  const тело = Buffer.concat([Buffer.from('WEBP', 'latin1'), ...куски]);
  const з = Buffer.alloc(8);
  з.write('RIFF', 0, 'latin1');
  з.writeUInt32LE(тело.length, 4);
  return Buffer.concat([з, тело]);
}

// Без потерь: байт 0x2f, потом 14 бит (ширина-1), 14 бит (высота-1), 4 бита прочего. Данные картинки — заглушка.
function данныеVP8L(ш, в) {
  const д = Buffer.alloc(5 + 8);
  д[0] = 0x2f;
  д.writeUInt32LE((((ш - 1) & 0x3fff) | (((в - 1) & 0x3fff) << 14)) >>> 0, 1);
  return д;
}
function webpVP8L(ш, в) {
  return riff([чанкWebp('VP8L', данныеVP8L(ш, в))]);
}

// Расширенный: 1 байт флагов, 3 зарезервированных, холст: ширина-1 и высота-1 по 24 бита.
function webpVP8X(ш, в) {
  const д = Buffer.alloc(10);
  д[0] = 0x10;
  д.writeUIntLE(ш - 1, 4, 3);
  д.writeUIntLE(в - 1, 7, 3);
  return riff([чанкWebp('VP8X', д), чанкWebp('VP8L', данныеVP8L(1, 1))]);
}

// Простой с потерями: 3 байта тега кадра, стартовый код 9d 01 2a, ширина и высота по 16 бит (14 бит + 2 бита масштаба).
function webpVP8(ш, в, масштабШирины = 0) {
  const д = Buffer.alloc(3 + 3 + 4 + 8);
  д.writeUIntLE(0 | (0 << 1) | (1 << 4) | (10 << 5), 0, 3); // ключевой кадр, версия 0, показывать, размер первой части
  д[3] = 0x9d;
  д[4] = 0x01;
  д[5] = 0x2a;
  д.writeUInt16LE(((масштабШирины & 3) << 14) | (ш & 0x3fff), 6);
  д.writeUInt16LE(в & 0x3fff, 8);
  return riff([чанкWebp('VP8 ', д)]);
}

function jpg() {
  const б = Buffer.alloc(64, 0x11);
  Buffer.from([0xff, 0xd8, 0xff, 0xe0, 0x00, 0x10]).copy(б, 0);
  Buffer.from('JFIF\0', 'latin1').copy(б, 6);
  return б;
}

