function запуститьАсинхронно(ср, аргументы) {
  return new Promise((готово) => {
    const п = cp.spawn(process.execPath, [ср.программа, ...аргументы, '--доска', ср.доска, '--корень', ср.корень], { stdio: ['ignore', 'pipe', 'pipe'] });
    let вывод = '';
    п.stdout.on('data', (д) => (вывод += д));
    п.stderr.on('data', (д) => (вывод += д));
    п.on('close', (код) => готово({ код, вывод }));
  });
}

async function проверкаГонки(у, ср0) {
  раздел(у, 'Одновременная запись: 8 процессов «добавить» разом (три волны)');
  let потеряно = 0;
  let упало = 0;
  for (let волна = 1; волна <= 3; волна++) {
    const ср = сДоской(ср0, `гонка-${волна}.json`);
    const процессы = [];
    for (let и = 1; и <= 8; и++) {
      const ключ = `гонка-${волна}-${и}`;
      процессы.push({ ключ, файл: положитьJson(ср, задача(ключ)) });
    }
    const итоги = await Promise.all(процессы.map((п) => запуститьАсинхронно(ср, ['добавить', п.файл]).then((р) => Object.assign(р, { ключ: п.ключ }))));
    let данные = null;
    try {
      данные = JSON.parse(fs.readFileSync(ср.доска, 'utf8'));
    } catch (е) {}
    проверь(у, `гонка ${волна}: файл доски после — целый JSON со списком «задачи»`, данные && Array.isArray(данные.задачи));
    const ключиНаДоске = new Set(данные ? данные.задачи.map((з) => з.ключ) : []);
    const успешные = итоги.filter((р) => р.код === 0);
    const потеряныЭтойВолны = успешные.filter((р) => !ключиНаДоске.has(р.ключ));
    потеряно += потеряныЭтойВолны.length;
    упало += итоги.length - успешные.length;
    проверь(у, `гонка ${волна}: каждая задача, чей процесс вернул код 0, есть на доске`, потеряныЭтойВолны.length === 0,
      `потеряно ${потеряныЭтойВолны.length} из ${успешные.length}: ${потеряныЭтойВолны.map((р) => р.ключ).join(', ')}`);
    проверь(у, `гонка ${волна}: все 8 процессов вернули код 0 (ни один не упал)`, успешные.length === 8,
      итоги.filter((р) => р.код !== 0).map((р) => `${р.ключ}: код ${р.код} ${р.вывод.trim().split('\n')[0]}`).join(' | '));
    const мусор = fs.readdirSync(ср.tmp).filter((и) => и.startsWith(`гонка-${волна}.json.`) && и.endsWith('.tmp'));
    проверь(у, `гонка ${волна}: не осталось временных файлов .tmp`, мусор.length === 0, мусор.join(', '));
  }
  у.заметки.push(`Гонка: потеряно задач при коде 0 — ${потеряно} из 24; процессов, упавших с ненулевым кодом — ${упало}.`);
}

// ---------- отпечаток настоящих файлов ----------

function отпечатокФайла(п) {
  return fs.existsSync(п) ? crypto.createHash('sha256').update(fs.readFileSync(п)).digest('hex') : '(нет файла)';
}

function отпечатокПапки(п) {
  if (!fs.existsSync(п)) return '(нет папки)';
  const строки = [];
  const обход = (д) => {
    for (const и of fs.readdirSync(д, { withFileTypes: true })) {
      const полный = path.join(д, и.name);
      if (и.isDirectory()) обход(полный);
      else строки.push(path.relative(п, полный) + ':' + fs.statSync(полный).size);
    }
  };
  обход(п);
  строки.sort();
  return crypto.createHash('sha256').update(строки.join('\n')).digest('hex') + ` (${строки.length} файлов)`;
}

function снятьОтпечатки(программа) {
  return { доска: отпечатокФайла(НАСТОЯЩАЯ_ДОСКА), картинки: отпечатокПапки(НАСТОЯЩИЕ_КАРТИНКИ), настоящаяПрограмма: отпечатокФайла(НАСТОЯЩАЯ_ПРОГРАММА) };
}

