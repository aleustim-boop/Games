  const ср = сДоской(ср0, 'переходы.json');
  const слова = path.join(ср.tmp, 'слова-переходы.txt');
  fs.writeFileSync(слова, 'Замечание.\n', 'utf8');
  const ключи = { ждёт: 'п-ждёт', 'в работе': 'п-работа', сдано: 'п-сдано', вернули: 'п-вернули', принято: 'п-принято' };
  const все = Object.values(ключи).map((к) => задача(к));
  проверь(у, 'переходы: пять задач добавлены', добав(ср, все).код === 0);
  for (const к of Object.values(ключи)) положитьКартинку(ср, `img/проба/${к}.png`, png(300, 200));
  // Приводим задачи в нужные статусы законными ходами.
  for (const к of ['п-работа', 'п-сдано', 'п-вернули', 'п-принято']) запуск(ср, ['взять', к]);
  for (const к of ['п-сдано', 'п-вернули', 'п-принято']) запуск(ср, ['сдать', к]);
  запуск(ср, ['вернуть', 'п-вернули', слова]);
