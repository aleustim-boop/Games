/** Список УРОВНИ из экрана «Захвата» (или его копии из --экран). Не нашёлся — пустой список. */
function прочитатьУровниЭкрана() {
  const путь = довод('--экран') ? path.resolve(довод('--экран')) : path.join(КОРЕНЬ, ЗАКАЗ.экран);
  let текст = '';
  try { текст = fs.readFileSync(путь, 'utf8'); } catch (сбой) { return []; }
  const строка = /const УРОВНИ = \[([^\]]*)\]/.exec(текст);
  if (!строка) return [];
  return (строка[1].match(/'([^']*)'/g) || []).map(с => с.slice(1, -1));
}

