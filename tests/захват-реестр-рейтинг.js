  проверить(!('безРейтинга' in з) && !('счёт' in з), '1) нет полей «безРейтинга» и «счёт»');
  проверить(Boolean(з.бот), '1) есть поле «бот»');
  проверить(бот.партияНеКорочеСекунд === ЗАКАЗ.порог, '1) бот.партияНеКорочеСекунд = ' + ЗАКАЗ.порог + ' (в записи: ' + бот.партияНеКорочеСекунд + ')');
