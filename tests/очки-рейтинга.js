/* =====================================================================
   ОЧКИ РЕЙТИНГА: сколько даёт партия и где стоят ограничители.

   Зачем эта проверка существует. Числа в таблице очков назвал владелец
   вслух, и они не «примерно такие»: даже ничья с живым человеком (5)
   стоит дороже победы над сложным ботом (2), а за поражение не платят
   вовсе — иначе двое договорившихся играют в поддавки. Поправит
   кто-нибудь одну цифру «для порядка», и смысл перевернётся молча.
   Заметит это владелец, а не мы.

   УМЕЕТ ЛИ ОНА КРАСНЕТЬ — да, и это видно по истории самих чисел.
   До 10 сентября в server/рейтинг.js стояла другая шкала: победа над
   сложным ботом 6, над обычным 3, над лёгким 1, ничья — половина цены,
   а поражение не доходило до начисления вовсе (в коде стояло
   «if (!игрок.победил) continue»). На той шкале провалились бы шесть
   пунктов из девяти. Потом поражение живому недолго стоило 3 очка —
   на той шкале покраснел бы первый пункт. Нарочной поломкой прогон
   не делался, экономили расход, но числа тут говорят сами.

   ЧТО ПРОВЕРЯЕМ:
     1) цена партии по трём исходам, с человеком и с каждым ботом;
     2) потолок очков от ботов — 12 в сутки;
     3) ограничитель сговора — с одним и тем же человеком в зачёт идут
        первые пять партий в сутки;
     4) он же не мешает тому, кто играет с разными, — до общего потолка
        в 60 очков;
     5) таблицы игр не смешиваются;
     6) старый файл рейтинга, где новых полей ещё нет, читается и
        не теряет накопленное.

   Боевых данных не касается: папка данных на время прогона уводится
   во временную (GAMES_DATA). Однажды проверки из tests/ уже стёрли
   настоящие данные владельца — второй раз этого быть не должно.

   Запуск: node tests/очки-рейтинга.js     Выход 0 — провалов нет.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

process.env.GAMES_DATA = fs.mkdtempSync(path.join(os.tmpdir(), 'очки-рейтинга-'));

const КОРЕНЬ = path.join(__dirname, '..');
const рейтинг = require(path.join(КОРЕНЬ, 'server', 'рейтинг.js'));

let ошибок = 0;

function равно(что, было, надо) {
  const ок = было === надо;
  if (!ок) ошибок++;
  console.log((ок ? '  ок     ' : '  ПРОВАЛ ') + что + ': ' + было + (ок ? '' : ' (ждали ' + надо + ')'));
}

/** Живой игрок за столом. Исход — 'победа', 'ничья' или 'поражение'. */
function человек(номер, исход) {
  return {
    номер: номер, имя: 'И' + номер, этоБот: false,
    победил: исход === 'победа', ничья: исход === 'ничья'
  };
}

/** Бот за столом того или иного уровня. */
function бот(уровень, исход) {
  return {
    этоБот: true, уровень: уровень,
    победил: исход === 'победа', ничья: исход === 'ничья'
  };
}

/** Сколько очков у игрока в этой игре сейчас. */
function очки(номер, игра) {
  const срез = рейтинг.срезДляИгрока(игра || 'дурак', номер);
  return срез.я ? срез.я.очки : 0;
}

console.log('=== Очки рейтинга ===\n');

console.log('1. Партия двух людей: победа 10, поражение 0');
рейтинг.учестьПартию('дурак', [человек(101, 'победа'), человек(102, 'поражение')]);
равно('победитель', очки(101), 10);
равно('проигравший — за поражение не платят', очки(102), 0);

console.log('2. Ничья двух людей: по 5 каждому');
рейтинг.учестьПартию('дурак', [человек(103, 'ничья'), человек(104, 'ничья')]);
равно('первый', очки(103), 5);
равно('второй', очки(104), 5);

console.log('3. Боты: сложный 2, обычный 1, лёгкий 0');
рейтинг.учестьПартию('дурак', [человек(105, 'победа'), бот('сложный', 'поражение')]);
равно('обыграл сложного', очки(105), 2);
рейтинг.учестьПартию('дурак', [человек(106, 'победа'), бот('обычный', 'поражение')]);
равно('обыграл обычного', очки(106), 1);
рейтинг.учестьПартию('дурак', [человек(107, 'победа'), бот('лёгкий', 'поражение')]);
равно('обыграл лёгкого — не даём ничего', очки(107), 0);

console.log('4. Проиграл боту или сыграл с ним вничью — ноль');
рейтинг.учестьПартию('дурак', [человек(108, 'поражение'), бот('сложный', 'победа')]);
равно('проиграл сложному', очки(108), 0);
рейтинг.учестьПартию('дурак', [человек(109, 'ничья'), бот('сложный', 'ничья')]);
равно('ничья со сложным', очки(109), 0);

console.log('5. Потолок ботов: 12 очков в сутки — это шесть побед над сложным');
for (let раз = 0; раз < 10; раз++) {
  рейтинг.учестьПартию('дурак', [человек(110, 'победа'), бот('сложный', 'поражение')]);
}
равно('десять побед над сложным', очки(110), 12);

console.log('6. Сговор ничьими: с одним человеком в зачёт первые пять партий в сутки');
for (let раз = 0; раз < 8; раз++) {
  рейтинг.учестьПартию('дурак', [человек(111, 'ничья'), человек(112, 'ничья')]);
}
равно('первый (пять ничьих по 5)', очки(111), 25);
равно('второй (пять ничьих по 5)', очки(112), 25);

console.log('7. А кто играет с разными — тому ограничитель не мешает, до потолка 60');
for (let раз = 0; раз < 8; раз++) {
  рейтинг.учестьПартию('дурак', [человек(113, 'победа'), человек(200 + раз, 'поражение')]);
}
равно('восемь побед над разными людьми', очки(113), 60);

console.log('8. Игры не смешиваются');
рейтинг.учестьПартию('шашки', [человек(101, 'победа'), человек(114, 'поражение')]);
равно('в шашках', очки(101, 'шашки'), 10);
равно('в дураке не изменилось', очки(101, 'дурак'), 10);

console.log('9. Старый файл без новых полей читается и не теряет накопленное');
/* Отдельным процессом нарочно. Память рейтинга живёт внутри процесса,
   и «забытьВсё» файл заново НЕ читает — оно даёт проверкам чистый лист.
   Значит увидеть чтение файла можно только с чистого запуска. */
равно('накопленное на месте и новая победа прибавилась',
      прогонСоСтарымФайлом(), '30 40');

/**
 * Записать файл рейтинга в старом виде (новых полей в нём нет) и
 * прочитать его отдельным запуском. Отвечает «сколько было сколько стало».
 */
function прогонСоСтарымФайлом() {
  const место = fs.mkdtempSync(path.join(os.tmpdir(), 'старый-рейтинг-'));
  const сейчас = new Date();
  const два = (ч) => String(ч).padStart(2, '0');
  const день = сейчас.getFullYear() + '-' + два(сейчас.getMonth() + 1) + '-' + два(сейчас.getDate());
  fs.writeFileSync(path.join(место, 'рейтинг.json'), JSON.stringify({
    игроки: [{
      игра: 'дурак', номер: 555001, имя: 'Старожил', очки: 30, побед: 3,
      ничьих: 0, партий: 5, деньБотов: '', очкиОтБотовЗаДень: 0,
      последняяИгра: день
    }]
  }), 'utf8');

  const код = 'const р=require(' + JSON.stringify(path.join(КОРЕНЬ, 'server', 'рейтинг.js')) + ');' +
    'const было=р.срезДляИгрока("дурак",555001).я.очки;' +
    'р.учестьПартию("дурак",[{номер:555001,этоБот:false,победил:true},' +
    '{номер:555002,этоБот:false,победил:false}]);' +
    'const стало=р.срезДляИгрока("дурак",555001).я.очки;' +
    'console.log(было+" "+стало);';

  const запуск = require('child_process').spawnSync(process.execPath, ['-e', код], {
    env: Object.assign({}, process.env, { GAMES_DATA: место }),
    encoding: 'utf8'
  });
  return (запуск.stdout || '').trim() || ('не запустилось: ' + (запуск.stderr || '').trim().slice(0, 120));
}

console.log('\n----------------------------------------');
console.log('ПРОВАЛОВ: ' + ошибок);
process.exit(ошибок ? 1 : 0);
