/** Получить поле поПравилу из записи напрямую (для проверки внутренней структуры). */
function получитьПоловину(игра, номер, правило) {
  рейтинг.забытьВсё();
  // Пусто, но нужно, чтобы таблица инициализировалась
  const срез = рейтинг.срезДляИгрока(игра, номер);
  // Добавим партию с признаком правила, чтобы запись появилась
  рейтинг.учестьПартию(игра, [{
    номер: номер,
    имя: 'Тест',
    этоБот: false,
    переводной: правило === 'переводной',
    победил: false,
    ничья: false
  }, {
    этоБот: true,
    уровень: 'лёгкий',
    победил: true,
    ничья: false
  }]);
  const запись = рейтинг.срезДляИгрока(игра, номер);
  if (!запись.я) return { очки: 0, побед: 0, ничьих: 0, партий: 0 };
  // Внутренняя структура: нам нужен доступ к поПравилу
  // Используем обратный инженеринг через порядок и списокДляИгрока
  const всеПоПравилу = рейтинг.порядок(игра, правило);
  for (const запись of всеПоПравилу) {
    if (запись.номер === номер) {
      // Нашли - это уже отсортировано по правилу
      return { очки: запись.очки, побед: запись.побед, партий: запись.партий };
    }
  }
  return { очки: 0, побед: 0, ничьих: 0, партий: 0 };
}

