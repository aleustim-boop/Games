function замерОкнаИКнопки() {
  const окно = document.getElementById('mono-modal');
  const плашка = document.getElementById('плашка-досрочно');
  const W = document.documentElement.clientWidth, H = window.innerHeight;
  const итог = {
    окноЕсть: Boolean(окно), окноОткрыто: Boolean(окно && окно.open), модальное: Boolean(окно && окно.open && окно.matches(':modal')),
    слова: окно ? окно.innerText.replace(/\s+/g, ' ').trim() : '', кнопки: {}
  };
  ['за', 'против'].forEach(function (имя) {
    const кнопка = document.querySelector('#плашка-досрочно .плашка-досрочно__' + имя);
    if (!кнопка) { итог.кнопки[имя] = { есть: false }; return; }
    const р = кнопка.getBoundingClientRect();
    const рп = плашка.getBoundingClientRect();
    const о = окно && окно.open ? окно.getBoundingClientRect() : null;
    // Пять точек: четыре угла (на 2px внутрь) и центр. У скруглённой кнопки угол попадает
    // на плашку за ней, поэтому требуем «точка в плашке и не в окне».
    const точки = [[р.left + 2, р.top + 2], [р.right - 2, р.top + 2], [р.left + 2, р.bottom - 2], [р.right - 2, р.bottom - 2], [(р.left + р.right) / 2, (р.top + р.bottom) / 2]];
    const сверху = точки.map(function (т) { const ц = document.elementFromPoint(т[0], т[1]); return Boolean(ц) && плашка.contains(ц) && !(окно && окно.contains(ц)); });
    итог.кнопки[имя] = {
      есть: true, текст: кнопка.textContent.trim(),
      видна: р.width > 0 && р.height > 0 && !кнопка.closest('.скрыт'),
      вЭкране: р.left >= -0.5 && р.top >= -0.5 && р.right <= W + 0.5 && р.bottom <= H + 0.5,
      вПлашке: р.left >= рп.left - 0.5 && р.right <= рп.right + 0.5,
      точекСверху: сверху.filter(Boolean).length, перекрытоОкном: Boolean(о) && р.left < о.right && р.right > о.left && р.top < о.bottom && р.bottom > о.top,
      левый: Math.round(р.left), правый: Math.round(р.right), верх: Math.round(р.top), низ: Math.round(р.bottom)
    };
  });
  if (плашка) итог.плашкаНиз = плашка.getBoundingClientRect().bottom;
  if (окно && окно.open) { const о = окно.getBoundingClientRect(); итог.окноВерх = о.top; итог.окноНиз = о.bottom; итог.окноВЭкране = о.bottom <= H + 0.5; }
  // Стол под окном: кнопки стола (кнопка хода у человека, «Увеличить поле» всегда) не принимают нажатия.
  const ход = document.querySelector('.mono-layout button');
  итог.ходЕсть = Boolean(ход);
  итог.ходНажимается = ход ? getComputedStyle(ход).pointerEvents !== 'none' : null;
  итог.классСтола = document.getElementById('экран-игры').classList.contains('mono-окно-не-модальное');
  итог.фокусВОкне = Boolean(окно && окно.contains(document.activeElement) && document.activeElement !== окно);
  итог.фокусТег = document.activeElement ? document.activeElement.tagName : '';
  return итог;
}

function замерЛобби() {
  const лобби = document.getElementById('экран-лобби');
  const бот = document.getElementById('mono-bots');
  const полоса = document.querySelector('#экран-лобби .нижние-вкладки');
  const заметка = document.getElementById('mono-restore-note');
  const виден = function (е) {
    if (!е || е.closest('.скрыт')) return false;
    const р = е.getBoundingClientRect(), с = getComputedStyle(е);
    return р.width > 0 && р.height > 0 && с.display !== 'none' && с.visibility !== 'hidden';
  };
  // Прокрутка до конца и лобби, и страницы: что из них листается, то и листаем.
  лобби.scrollTop = лобби.scrollHeight;
  window.scrollTo(0, document.documentElement.scrollHeight);
  const итог = { лоббиЕсть: Boolean(лобби), ботЕсть: Boolean(бот), полосаЕсть: Boolean(полоса), заметкаЕсть: Boolean(заметка), заметкаВидна: виден(заметка), H: window.innerHeight };
  if (бот) итог.ботНиз = бот.getBoundingClientRect().bottom;
  if (полоса) итог.полосаВерх = полоса.getBoundingClientRect().top;
  if (бот && полоса) {
    const р = бот.getBoundingClientRect();
    const ц = document.elementFromPoint((р.left + р.right) / 2, р.bottom - 3);
    итог.низКнопкиСверху = Boolean(ц) && (ц === бот || бот.contains(ц));
  }
  if (заметка && виден(заметка)) {
    итог.заметкаНиз = заметка.getBoundingClientRect().bottom;
    // Следующий видимый блок после плашки: «Продолжить» или карточка профиля.
    let сосед = заметка.nextElementSibling;
    while (сосед && !виден(сосед)) сосед = сосед.nextElementSibling;
    итог.соседЕсть = Boolean(сосед);
    if (сосед) итог.соседВерх = сосед.getBoundingClientRect().top;
  }
  return итог;
}

