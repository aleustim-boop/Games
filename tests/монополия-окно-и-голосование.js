function запуститьСПодменой(подмены) {
  const довод = [];
  Object.keys(подмены).forEach(function (имя) { довод.push('--подмена', имя + '=' + подмены[имя]); });
  return spawnSync(process.execPath, [__filename].concat(довод), { encoding: 'utf8', timeout: 400000, cwd: ПРОЕКТ });
}

function ломать() {
  console.log('=== Ломающий прогон: порченые КОПИИ экрана и стилей, каждая обязана покраснеть ===');
  const данная = process.argv[process.argv.indexOf('--сломать') + 1];
  const задана = данная && !данная.startsWith('--');
  const папка = задана ? path.resolve(данная) : fs.mkdtempSync(path.join(os.tmpdir(), 'монополия-окно-лом-'));
  fs.mkdirSync(папка, { recursive: true });
  const сделанные = [];
  let ждали = 0;
  let ладно = 0;
  try {
    const читать = function (имя) { return fs.readFileSync(path.join(ПРОЕКТ, имя), 'utf8'); };
    const копияЦелая = function (имя) {
      const куда = path.join(папка, 'целая-' + имя.replace(/[\\/]/g, '_'));
      fs.writeFileSync(куда, читать(имя), 'utf8');
      сделанные.push(куда);
      return куда;
    };

    ждали++;
    const контроль = запуститьСПодменой({ [ИМЯ_ЭКРАНА]: копияЦелая(ИМЯ_ЭКРАНА), [ИМЯ_СЦЕНЫ]: копияЦелая(ИМЯ_СЦЕНЫ) });
    const зелёный = контроль.status === 0;
    console.log((зелёный ? '  ок    — ' : '  ПЛОХО — ') + 'контрольная НЕпорченая копия проходит (код ' + контроль.status + ')');
    if (зелёный) ладно++; else console.log((контроль.stdout || '') + (контроль.stderr || ''));

    ПОРЧИ.forEach(function (порча, и) {
      ждали++;
      const текст = читать(порча.файл);
      const частей = текст.split(порча.было).length - 1;
      if (частей !== 1) {
        console.log('  ПЛОХО — [' + порча.что + '] строка порчи в ' + порча.файл + ' встречается ' + частей + ' раз (нужно ровно 1) — портить нечего');
        return;
      }
      const подмены = { [ИМЯ_ЭКРАНА]: копияЦелая(ИМЯ_ЭКРАНА), [ИМЯ_СЦЕНЫ]: копияЦелая(ИМЯ_СЦЕНЫ) };
      const испорченная = path.join(папка, 'порча-' + (и + 1) + '-' + порча.файл.replace(/[\\/]/g, '_'));
      fs.writeFileSync(испорченная, текст.replace(порча.было, function () { return порча.стало; }), 'utf8');
      сделанные.push(испорченная);
      подмены[порча.файл] = испорченная;
      const прогон = запуститьСПодменой(подмены);
      const строки = (прогон.stdout || '').split('\n');
      const покраснела = прогон.status === 1 && строки.some(function (с) { return с.indexOf('ПЛОХО') !== -1 && с.indexOf(порча.метка) !== -1; });
      console.log((покраснела ? '  ок    — ' : '  ПЛОХО — ') + 'порча «' + порча.что + '» покраснела на ' + порча.метка + (покраснела ? '' : ' (код ' + прогон.status + ')'));
      if (покраснела) ладно++; else console.log((прогон.stdout || '') + (прогон.stderr || ''));
    });
  } finally {
    сделанные.forEach(function (ф) { fs.rmSync(ф, { force: true }); });
    if (!задана) fs.rmSync(папка, { recursive: true, force: true });
    console.log('Временные копии убраны: ' + папка);
  }
  console.log('\nИтого проверок: ' + ждали + ', провалов: ' + (ждали - ладно));
  process.exitCode = ждали === ладно ? 0 : 1;
}

/* ---------- Запуск ---------- */

if (process.argv.includes('--сломать')) {
  ломать();
} else {
  const подмены = подменыИзДоводов();
  const нет = Object.keys(подмены).filter(function (и) { return !fs.existsSync(подмены[и]); });
  if (нет.length) { console.error('ПРОВАЛ: нет файла-копии для ' + нет.join(', ')); process.exit(1); }
  прогнать(подмены).then(function () {
    console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
    process.exit(провалов > 0 ? 1 : 0);
  }, function (е) {
    console.error('ПРОВАЛ ЗАПУСКА: ' + (е && е.stack || е));
    process.exit(1);
  });
}
