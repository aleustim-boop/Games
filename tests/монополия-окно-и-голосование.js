/** (а) окно и голосование; порядок: 'окно-первым' или 'голосование-первым'. */
async function окноИГолосование(браузер, адрес, размер, окноВид, порядок, снимать) {
  const п = размер.w + 'px [голос, ' + окноВид.имя + ', ' + порядок + '] ';
  console.log('\n--- ' + размер.w + '×' + размер.h + ' · окно «' + окноВид.имя + '» и голосование · ' + порядок + ' ---');
  const ошибки = [];
  const { контекст, страница } = await новаяСтраница(браузер, размер, ошибки);
  try {
    await открытьМонополию(страница, адрес);
    await начатьПартиюСБотами(страница);
    const открытьОкно = async function () {
      const есть = (await страница.locator(окноВид.селектор).count()) === 1;
      if (!проверить(есть, п + '[голос] кнопка «' + окноВид.имя + '» (' + окноВид.селектор + ') найдена (не нашли — провал)')) return false;
      await страница.click(окноВид.селектор);
      await страница.waitForTimeout(400);
      return true;
    };
    const поле = '#mono-modal-body input';
    if (порядок === 'окно-первым') {
      if (!await открытьОкно()) return;
      if (окноВид.имя === 'Обмен') {
        const поля = await страница.locator(поле).count();
        if (проверить(поля > 0, п + '[фокус] в окне обмена есть поле ввода (не нашли — провал)')) await страница.locator(поле).first().focus();
      }
      await страница.evaluate(показатьГолосование);
    } else {
      await страница.evaluate(показатьГолосование);
      if (!await открытьОкно()) return;
    }
    await страница.waitForTimeout(500);
    const до = await страница.evaluate(замерОкнаИКнопки);
    проверить(до.окноЕсть && до.окноОткрыто, п + '[голос] окно открыто (узел есть: ' + до.окноЕсть + ', открыто: ' + до.окноОткрыто + ')');
    проверить(до.модальное === false, п + '[голос] пока идёт голосование окно не модальное');
    ['за', 'против'].forEach(function (имя) {
      const к = до.кнопки[имя];
      if (!проверить(Boolean(к && к.есть && к.видна), п + '[голос] кнопка голоса «' + имя + '» есть и видна (не нашли — провал)')) return;
      проверить(к.вЭкране && к.вПлашке, п + '[перекрытие] кнопка «' + к.текст + '» целиком в экране и в плашке (' + к.левый + '–' + к.правый + ' по ширине, ' + к.верх + '–' + к.низ + ' по высоте, экран ' + размер.w + '×' + размер.h + ')');
      проверить(к.точекСверху === 5, п + '[перекрытие] у кнопки «' + к.текст + '» все пять точек (углы и центр) — в плашке, а не под окном (' + к.точекСверху + ' из 5)');
      проверить(!к.перекрытоОкном, п + '[перекрытие] рамка кнопки «' + к.текст + '» не пересекается с рамкой окна');
    });
    проверить(до.окноВерх !== undefined && до.окноВерх >= до.плашкаНиз - 0.5, п + '[перекрытие] окно начинается ниже плашки (плашка до ' + Math.round(до.плашкаНиз) + ', окно с ' + Math.round(до.окноВерх) + ')');
    проверить(до.окноВЭкране === true, п + '[перекрытие] окно целиком влезает вниз экрана (низ окна ' + Math.round(до.окноНиз) + ', экран ' + размер.h + ')');
    проверить(до.ходЕсть && до.классСтола && до.ходНажимается === false, п + '[стол] стол под окном не нажимается: кнопка хода есть (' + до.ходЕсть + '), класс на экране игры (' + до.классСтола + '), нажимается (' + до.ходНажимается + ')');
    if (окноВид.имя === 'Обмен' && порядок === 'окно-первым') проверить(до.фокусВОкне && до.фокусТег === 'INPUT', п + '[фокус] после переоткрытия фокус остался в поле ввода окна (сейчас: ' + до.фокусТег + ')');
    if (снимать) await снимок(страница, размер.w + '-' + окноВид.имя + '-' + порядок);

    // Настоящее нажатие мышью: playwright убеждается, что кнопку ничто не перекрывает.
    let нажато = true;
    try { await страница.locator('#плашка-досрочно .плашка-досрочно__за').click({ timeout: 4000 }); } catch (е) { нажато = false; }
    await страница.waitForTimeout(300);
    const голоса = await страница.evaluate(function () { return window.__голоса; });
    проверить(нажато && Array.isArray(голоса) && голоса.length === 1 && голоса[0] === true, п + '[голос] нажатие мышью дошло до двери голоса (нажато: ' + нажато + ', голосов: ' + JSON.stringify(голоса) + ')');
    const после = await страница.evaluate(замерОкнаИКнопки);
    проверить(после.окноОткрыто && после.слова === до.слова, п + '[голос] после голоса окно открыто и слова те же');

    // Окно закрыто посреди голосования: стол снова нажимается, класс снят.
    await страница.click('#mono-close');
    await страница.waitForTimeout(300);
    const закрыто = await страница.evaluate(замерОкнаИКнопки);
    проверить(!закрыто.окноОткрыто && !закрыто.классСтола && закрыто.ходНажимается === true, п + '[закрытие] окно закрыто во время голосования: стол снова нажимается и класс снят (открыто: ' + закрыто.окноОткрыто + ', класс: ' + закрыто.классСтола + ', ход нажимается: ' + закрыто.ходНажимается + ')');
    await страница.evaluate(убратьГолосование);
    await страница.waitForTimeout(300);
    const концеГолоса = await страница.evaluate(замерОкнаИКнопки);
    проверить(!концеГолоса.окноОткрыто && !концеГолоса.классСтола, п + '[закрытие] голосование кончилось после закрытия окна: окно закрыто, класса нет');

    // Теперь окно открывается обычным, модальным путём; голосование потом начинается и кончается при открытом окне.
    if (!await открытьОкно()) return;
    const снова = await страница.evaluate(замерОкнаИКнопки);
    проверить(снова.окноОткрыто && снова.модальное === true && !снова.классСтола, п + '[голос] без голосования окно снова модальное, класса стола нет');
    await страница.evaluate(показатьГолосование);
    await страница.waitForTimeout(400);
    const внутри = await страница.evaluate(замерОкнаИКнопки);
    проверить(внутри.окноОткрыто && внутри.модальное === false && внутри.классСтола, п + '[голос] голосование началось при открытом окне: окно стало немодальным, класс стола стоит');
    await страница.evaluate(убратьГолосование);
    await страница.waitForTimeout(400);
    const конец = await страница.evaluate(замерОкнаИКнопки);
    проверить(конец.окноОткрыто && конец.модальное === true && !конец.классСтола, п + '[голос] когда голосование кончилось, окно открыто, снова модальное, класс стола снят');
    проверить(ошибки.length === 0, п + 'ошибок в консоли нет' + (ошибки.length ? ': ' + ошибки.join(' | ') : ''));
  } catch (е) {
    проверить(false, п + 'сценарий не дошёл до конца: ' + String(е && е.message).split('\n')[0]);
  } finally {
    await контекст.close();
  }
}

/** (б) лобби: состояние 'плашка' (негодная запись) или 'продолжить' (годная запись). */
async function лобби(браузер, адрес, размер, состояние, ключ, снимать) {
  const п = размер.w + 'px [лобби, ' + состояние + '] ';
  console.log('\n--- ' + размер.w + '×' + размер.h + ' · лобби · ' + состояние + ' ---');
  const ошибки = [];
  const { контекст, страница } = await новаяСтраница(браузер, размер, ошибки);
  try {
    await открытьМонополию(страница, адрес);
    if (состояние === 'плашка') {
      const негодная = { version: 1, n: 4, seed: 17, actions: [{ p: 3, move: { type: 'buy' } }], id: 1, result: false };
      await страница.evaluate(function (д) { localStorage.setItem(д.к, JSON.stringify(д.з)); }, { к: ключ, з: негодная });
    } else {
      await начатьПартиюСБотами(страница);
    }
    await открытьМонополию(страница, адрес);
    const м = await страница.evaluate(замерЛобби);
    await страница.waitForTimeout(300);
    проверить(м.лоббиЕсть && м.ботЕсть && м.полосаЕсть, п + '[полоса] в лобби есть кнопка «Играть с ботами» и нижняя полоса (не нашли — провал)');
    проверить(м.ботНиз !== undefined && м.полосаВерх !== undefined && м.ботНиз <= м.полосаВерх + 0.5,
      п + '[полоса] низ кнопки «Играть с ботами» выше верха нижней полосы после прокрутки (низ кнопки ' + Math.round(м.ботНиз) + ', верх полосы ' + Math.round(м.полосаВерх) + ')');
    проверить(м.низКнопкиСверху === true, п + '[полоса] у нижнего края кнопки лежит сама кнопка, полоса её не закрывает');
    if (состояние === 'плашка') {
      проверить(м.заметкаЕсть && м.заметкаВидна, п + '[зазор] плашка «Сохранённая партия не подошла…» есть и видна (не нашли — провал)');
      проверить(м.соседЕсть && м.соседВерх - м.заметкаНиз >= МИН_ЗАЗОР - 0.01,
        п + '[зазор] между плашкой и карточкой профиля не меньше ' + МИН_ЗАЗОР + 'px (плашка до ' + Math.round(м.заметкаНиз) + ', следующий блок с ' + Math.round(м.соседВерх) + ')');
    }
    if (снимать) await снимок(страница, размер.w + '-лобби-' + состояние);
    проверить(ошибки.length === 0, п + 'ошибок в консоли нет' + (ошибки.length ? ': ' + ошибки.join(' | ') : ''));
  } catch (е) {
    проверить(false, п + 'сценарий не дошёл до конца: ' + String(е && е.message).split('\n')[0]);
  } finally {
    await контекст.close();
  }
}

async function прогнать(подмены) {
  const файлЭкрана = подмены[ИМЯ_ЭКРАНА] || path.join(ПРОЕКТ, ИМЯ_ЭКРАНА);
  const ключ = найтиКлюч(fs.readFileSync(файлЭкрана, 'utf8'));
  console.log('=== Монополия: окно сделки и голосование; лобби на узком экране ===');
  if (!проверить(Boolean(ключ), '[ключ] ключ сохранённой партии найден в js/монополия-экран.js')) return;
  const сервер = await поднятьСервер(подмены);
  const адрес = 'http://127.0.0.1:' + сервер.address().port;
  console.log('стенд: ' + адрес + ' (свой, не боевой 8790)' + (Object.keys(подмены).length ? '; подмены: ' + Object.keys(подмены).join(', ') : ''));
  const снимать = Object.keys(подмены).length === 0;
  let браузер = null;
  try {
    браузер = await chromium.launch();
    for (const р of РАЗМЕРЫ) {
      for (const окноВид of ОКНА) {
        await окноИГолосование(браузер, адрес, р, окноВид, 'окно-первым', снимать);
        await окноИГолосование(браузер, адрес, р, окноВид, 'голосование-первым', false);
      }
      await лобби(браузер, адрес, р, 'плашка', ключ, снимать);
      await лобби(браузер, адрес, р, 'продолжить', ключ, false);
    }
  } finally {
    if (браузер) await браузер.close();
    сервер.close();
    console.log('Стенд закрыт (процесс ' + process.pid + ').');
  }
}

