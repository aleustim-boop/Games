/** Раздача файлов проекта на свободном порту; «подмены» — карта
 *  {url-путь: файл-на-диске} для ломающих запусков (на обычном запуске
 *  карта пуста, раздаём только КОРЕНЬ). */
function поднятьРаздачу(подмены) {
  const карта = подмены || {};
  const сервер = http.createServer(function (запрос, ответ) {
    let путь = запрос.url.split('?')[0].split('#')[0];
    try { путь = decodeURIComponent(путь); } catch (ошибка) { /* оставим как есть */ }
    const файл = карта[путь] || path.join(КОРЕНЬ, путь === '/' ? 'шахматы.html' : путь.slice(1));
    fs.readFile(файл, function (беда, тело) {
      if (беда) { ответ.writeHead(404); ответ.end('нет такого файла'); return; }
      ответ.writeHead(200, { 'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'text/plain' });
      ответ.end(тело);
    });
  });
  return new Promise((готово) => сервер.listen(0, '127.0.0.1', () => готово(сервер)));
}

/* ---------------------------------------------------------------------
   ЛОМАЮЩИЙ ЗАПУСК --сломать: портим КОПИЮ шахматы.html — убираем целиком
   карточку «лобби-друзья», карточек-входов остаётся три вместо четырёх.
   Первая же проверка («ровно четыре карточки») обязана покраснеть. Файл
   проекта не трогаем и не откатываем — только копию.
   --------------------------------------------------------------------- */
function приготовитьИспорченнуюКопиюЛобби() {
  const путьКФайлу = path.join(КОРЕНЬ, 'шахматы.html');
  const исходник = fs.readFileSync(путьКФайлу, 'utf8');
  const образецНачало = /<button id="лобби-друзья"[\s\S]*?<\/button>\r?\n/;
  if (!образецНачало.test(исходник)) {
    console.error('ломающий запуск --сломать сломался: в шахматы.html не нашлась карточка ' +
      '«лобби-друзья» в ожидаемом виде — ноль замен, портить нечего (провал, а не пропуск)');
    process.exit(2);
  }
  const испорченный = исходник.replace(образецНачало, '');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'шахматы-лобби-'));
  const копия = path.join(папка, 'шахматы.html');
  fs.writeFileSync(копия, испорченный, 'utf8');
  console.log('ломающий запуск --сломать: испорченная копия лежит в ' + копия);
  return { копия, папка };
}

