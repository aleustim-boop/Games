'use strict';

/* =====================================================================
   СНИМОК ПАРТИИ НАРД: УЕХАЛ ЧЕРЕЗ JSON И ВЕРНУЛСЯ ТЕМ ЖЕ

   Зачем это. По сети партия поедет не объектом в памяти, а простым
   текстом JSON: сервер снимает «картинкуПартии», отправляет, а на той
   стороне из неё снова собирают партию. Если в снимок не попадёт хоть
   одно поле хода — кубики, «сколько обязан сыграть», снятые с головы, —
   у сервера и у экрана будут РАЗНЫЕ списки ходов, и игрок получит отказ
   на законном ходу. Поймать такое глазами нельзя: расходится оно раз в
   сотню позиций.

   Как проверяем. Играем 300 случайных партий (150 коротких и 150
   длинных) до победы и после КАЖДОГО броска и КАЖДОГО перемещения
   делаем так:

       партия → картинкаПартии → JSON.stringify → JSON.parse
              → партияИзКартинки → сравниваем с оригиналом

   Сравниваются три вещи:
     1) отпечатокПозиции — та же ли доска и тот же ли чей ход;
     2) имена и места всех тридцати шашек — имя обязано доехать, иначе
        узел шашки на экране сочтут новым и вместо движения будет скачок;
     3) список возможныеШаги — самое главное: он считается из кубиков,
        максимума, головы и обязательного кубика разом, и разойдётся,
        если потеряется любое из них.

   Зерно случайности постоянное: прогон повторяется слово в слово, и
   найденная беда воспроизводится с первого раза.

   ЛОМАЮЩИЙ ЗАПУСК (проверка умеет краснеть):

       node tests/нарды-снимок-партии.js --сломать

   Копирует js/нарды-правила.js во временную папку, в КОПИИ выкидывает
   из снимка поле «кубики» и гоняет по копии те же 300 партий. Провалов
   обязано быть больше нуля. Настоящий файл проекта не трогается.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

const ПУТЬ_ПРАВИЛ = path.join(__dirname, '..', 'js', 'нарды-правила.js');

const ПАРТИЙ = 300;            // всего партий: пополам короткие и длинные
const ЗЕРНО = 20260922;        // постоянное — прогон обязан повторяться
const ПРЕДОХРАНИТЕЛЬ = 500;    // ходов на партию, заведомо с запасом

/** Свой генератор случайных чисел: с ним прогон повторяется слово в слово. */
function генератор(семя) {
  let s = семя >>> 0;
  return function () { s = (Math.imul(s, 1664525) + 1013904223) >>> 0; return s / 4294967296; };
}

/** Список возможных перемещений одной строкой — так его легко сравнивать. */
function шагиСтрокой(Правила, партия) {
  return Правила.возможныеШаги(партия).map(function (ш) {
    return ш.фишка + ' ' + ш.откуда + '>' + ш.куда + ' к' + ш.кубик +
           (ш.побита ? ' бьёт ' + ш.побита : '') + (ш.вынос ? ' вне' : '');
  }).sort().join(' | ');
}

/** Имена и места всех тридцати шашек одной строкой. */
function фишкиСтрокой(Правила, партия) {
  return Правила.всеФишки(партия).map(function (ф) {
    return ф.имя + ':' + ф.место + ':' + ф.пункт + ':' + ф.слой;
  }).join(' ');
}

/** Та самая дорога по сети: снимок → текст → снимок → партия. */
function черезСеть(Правила, партия) {
  return Правила.партияИзКартинки(JSON.parse(JSON.stringify(Правила.картинкаПартии(партия))));
}

/** Пустой счёт прогона. */
function новыйСчёт() {
  return { партий: 0, ходов: 0, проверок: 0, провалов: 0, примеры: [] };
}

/** Одно сравнение. Не сошлось — провал, первые пять расхождений покажем. */
function сверить(счёт, где, ожидалось, пришло) {
  счёт.проверок++;
  if (ожидалось === пришло) return true;
  счёт.провалов++;
  if (счёт.примеры.length < 5) {
    счёт.примеры.push(где + '\n      у партии:       ' + обрезать(ожидалось) +
                      '\n      у снимка:       ' + обрезать(пришло));
  }
  return false;
}

function обрезать(что) {
  const текст = String(что);
  return текст.length > 160 ? текст.slice(0, 160) + '…' : текст;
}

/** Беда, из-за которой партия не доиграна: тоже провал, а не пропуск. */
function беда(счёт, текст) {
  счёт.проверок++;
  счёт.провалов++;
  if (счёт.примеры.length < 5) счёт.примеры.push(текст);
}

/**
 * Одна партия от начала до победы. После каждого броска и каждого
 * перемещения — сверка оригинала с тем, что вернулось из снимка.
 */
function сыгратьПартию(Правила, счёт, вид, случайно, номер) {
  const где = вид + ', партия ' + номер;
  const партия = Правила.создатьПартию({
    вид: вид,
    первый: случайно() < 0.5 ? Правила.БЕЛЫЕ : Правила.ЧЁРНЫЕ
  });
  let ходов = 0;

  while (!Правила.партияЗавершена(партия) && ходов < ПРЕДОХРАНИТЕЛЬ) {
    const кубики = [1 + Math.floor(случайно() * 6), 1 + Math.floor(случайно() * 6)];

    /* Снимок ДО броска. Обеим партиям кидаем одни и те же кубики и
       сравниваем, что они предложат играть. */
    const доБроска = черезСеть(Правила, партия);
    сверить(счёт, где + ', ход ' + ходов + ': позиция до броска',
      Правила.отпечатокПозиции(партия), Правила.отпечатокПозиции(доБроска));
    сверить(счёт, где + ', ход ' + ходов + ': имена шашек до броска',
      фишкиСтрокой(Правила, партия), фишкиСтрокой(Правила, доБроска));

    Правила.бросить(партия, кубики);
    Правила.бросить(доБроска, кубики);
    сверить(счёт, где + ', ход ' + ходов + ': шаги после одного и того же броска ' + кубики.join('-'),
      шагиСтрокой(Правила, партия), шагиСтрокой(Правила, доБроска));
    сверить(счёт, где + ', ход ' + ходов + ': сколько кубиков обязан сыграть',
      Правила.максимумКубиков(партия), Правила.максимумКубиков(доБроска));

    /* Полуходы. Снимок посреди хода — самое хрупкое место: в нём живут
       недоигранные кубики, уже сделанные перемещения и голова. */
    let шаги = Правила.возможныеШаги(партия);
    while (шаги.length) {
      const посреди = черезСеть(Правила, партия);
      сверить(счёт, где + ', ход ' + ходов + ': позиция посреди хода',
        Правила.отпечатокПозиции(партия), Правила.отпечатокПозиции(посреди));
      сверить(счёт, где + ', ход ' + ходов + ': имена шашек посреди хода',
        фишкиСтрокой(Правила, партия), фишкиСтрокой(Правила, посреди));
      сверить(счёт, где + ', ход ' + ходов + ': шаги посреди хода',
        шагиСтрокой(Правила, партия), шагиСтрокой(Правила, посреди));

      Правила.сделатьШаг(партия, шаги[Math.floor(случайно() * шаги.length)]);
      if (Правила.партияЗавершена(партия)) break;
      шаги = Правила.возможныеШаги(партия);
    }

    if (!Правила.партияЗавершена(партия) && !Правила.завершитьХод(партия)) {
      беда(счёт, где + ': ход не удалось завершить, игра встала');
      return;
    }
    ходов++;
  }

  if (!Правила.партияЗавершена(партия)) {
    беда(счёт, где + ': не доиграна за ' + ПРЕДОХРАНИТЕЛЬ + ' ходов');
    return;
  }

  /* Снимок готовой партии: итог обязан доехать целиком, иначе экран
     победы покажет пустое место. */
  const конец = черезСеть(Правила, партия);
  сверить(счёт, где + ': итог завершённой партии',
    JSON.stringify(Правила.итог(партия)), JSON.stringify(Правила.итог(конец)));
  сверить(счёт, где + ': позиция завершённой партии',
    Правила.отпечатокПозиции(партия), Правила.отпечатокПозиции(конец));

  счёт.партий++;
  счёт.ходов += ходов;
}

/** Весь прогон: половина партий коротких, половина длинных. */
function прогнать(Правила) {
  const счёт = новыйСчёт();
  const половина = Math.floor(ПАРТИЙ / 2);
  const виды = [[Правила.КОРОТКИЕ, половина], [Правила.ДЛИННЫЕ, ПАРТИЙ - половина]];
  for (const [вид, сколько] of виды) {
    const случайно = генератор(ЗЕРНО + (вид === Правила.КОРОТКИЕ ? 0 : 777));
    const началось = Date.now();
    const былоПровалов = счёт.провалов;
    for (let номер = 1; номер <= сколько; номер++) {
      сыгратьПартию(Правила, счёт, вид, случайно, номер);
    }
    console.log('  ' + вид + ': партий ' + сколько + ', провалов ' + (счёт.провалов - былоПровалов) +
                ', времени ' + ((Date.now() - началось) / 1000).toFixed(1) + ' с');
  }
  return счёт;
}

/** Напечатать итог прогона и вернуть, всё ли хорошо. */
function напечатать(счёт) {
  for (const пример of счёт.примеры) console.log('  РАСХОЖДЕНИЕ ' + пример);
  console.log('  Сыграно партий: ' + счёт.партий + ', ходов всего: ' + счёт.ходов);
  console.log('Итого проверок: ' + счёт.проверок + ', провалов: ' + счёт.провалов);
}

/* ---------------------------------------------------------------------
   ОБЫЧНЫЙ ЗАПУСК
   --------------------------------------------------------------------- */
function обычныйЗапуск() {
  console.log('=== Снимок партии нард: съездил через JSON и вернулся тем же ===\n');
  const Правила = require(ПУТЬ_ПРАВИЛ);
  const счёт = прогнать(Правила);
  console.log('');
  напечатать(счёт);

  /* Ноль сыгранных партий или ноль сравнений — это провал, а не пропуск:
     проверка, которая ничего не посмотрела, обязана краснеть. */
  if (счёт.партий < ПАРТИЙ) {
    console.log('ПЛОХО: доиграно ' + счёт.партий + ' партий из ' + ПАРТИЙ);
    process.exitCode = 1;
    return;
  }
  if (счёт.проверок === 0) {
    console.log('ПЛОХО: не сделано ни одного сравнения — проверка смотрит не туда');
    process.exitCode = 1;
    return;
  }
  if (счёт.провалов > 0) process.exitCode = 1;
  else console.log('Снимок и партия сходятся везде.');
}

/* ---------------------------------------------------------------------
   ЛОМАЮЩИЙ ЗАПУСК: портим КОПИЮ правил во временной папке.
   Файл проекта не трогаем и не откатываем — в нём может лежать чужая
   несохранённая работа.
   --------------------------------------------------------------------- */
function ломающийЗапуск() {
  console.log('=== Ломающий запуск: в копии правил снимок теряет кубики ===\n');
  const исходник = fs.readFileSync(ПУТЬ_ПРАВИЛ, 'utf8');

  const начало = исходник.indexOf('function картинкаПартии(партия) {');
  if (начало === -1) {
    console.log('ПЛОХО: в правилах не нашлась функция картинкаПартии — ломать нечего');
    process.exitCode = 1;
    return;
  }
  const конец = исходник.indexOf('\n}\n', начало);
  if (конец === -1) {
    console.log('ПЛОХО: не нашёлся конец функции картинкаПартии');
    process.exitCode = 1;
    return;
  }
  const тело = исходник.slice(начало, конец);
  const порченое = тело.replace('кубики: партия.кубики.slice(),', 'кубики: [],');
  if (порченое === тело) {
    console.log('ПЛОХО: в снимке не нашлась строка с кубиками — ломать нечего');
    process.exitCode = 1;
    return;
  }

  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'нарды-снимок-'));
  const копия = path.join(папка, 'нарды-правила.js');
  try {
    fs.writeFileSync(копия, исходник.slice(0, начало) + порченое + исходник.slice(конец), 'utf8');
    console.log('  порченая копия: ' + копия + '\n');
    const Порченые = require(копия);
    const счёт = прогнать(Порченые);
    console.log('');
    напечатать(счёт);
    if (счёт.провалов > 0) {
      console.log('Ломающий запуск покраснел, как и должен: проверка ловит потерю кубиков.');
    } else {
      console.log('ПЛОХО: порченые правила прошли проверку — значит, она смотрит не туда');
      process.exitCode = 1;
    }
  } finally {
    /* Прибираем за собой: сначала файл, потом пустую папку. Ничего
       рекурсивного — сносить папки целиком в проекте запрещено. */
    try { fs.unlinkSync(копия); } catch (е) { /* уже нет — и ладно */ }
    try { fs.rmdirSync(папка); } catch (е) { /* уже нет — и ладно */ }
  }
}

if (process.argv.indexOf('--сломать') !== -1) ломающийЗапуск();
else обычныйЗапуск();
