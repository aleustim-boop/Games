function довод(имя) {
  const найден = process.argv.find(function (д) { return д.indexOf('--' + имя + '=') === 0; });
  return найден ? найден.slice(имя.length + 3) : '';
}

const проверки = [];
function проверить(условие, текст) {
  проверки.push({ ок: Boolean(условие), текст: текст });
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + текст);
}

function подождать() {
  return new Promise(function (готово) { setTimeout(готово, 5); });
}

async function подождатьПока(условие, сколькоРаз) {
  for (let i = 0; i < (сколькоРаз || 100); i++) {
    if (условие()) return true;
    await подождать();
  }
  return условие();
}

/* ---------------------------------------------------------------------
   Подменный сервер. ответы: { '/турнир-новости': [объект | 'сбой', …], … }.
   Объект — ответ сервера (JSON), 'сбой' — обрыв сети. Очередь кончилась —
   запрос висит (как долгий опрос, на который сервер пока не ответил).
   Возвращает запросы (журнал) и «разбудить» для висящих опросов.
   --------------------------------------------------------------------- */
function подменныйСервер(ответы) {
  const запросы = [];
  const висящие = [];
  function fetch(адрес, настройки) {
    let тело = null;
    try { тело = JSON.parse((настройки && настройки.body) || '{}'); } catch (сбой) { тело = null; }
    const дверь = String(адрес).replace(/^https?:\/\/[^/]+/, '');
    запросы.push({ дверь: дверь, тело: тело });
    const очередь = ответы[дверь];
    if (очередь && очередь.length) {
      const следующий = очередь.shift();
      if (следующий === 'сбой') return Promise.reject(new Error('нет сети'));
      return Promise.resolve({ ok: true, status: 200, json: function () { return Promise.resolve(следующий); } });
    }
    return new Promise(function (готово) {
      висящие.push({ дверь: дверь, ответить: function (данные) {
        готово({ ok: true, status: 200, json: function () { return Promise.resolve(данные); } });
      } });
    });
  }
  return { fetch: fetch, запросы: запросы, висящие: висящие };
}

function сколько(сервер, дверь) {
  return сервер.запросы.filter(function (з) { return з.дверь === дверь; }).length;
}

/** Поднять сеть.js с подменным сервером. Паузы после сбоя ужимаем до нуля. */
function поднятьСеть(исходник, ответы, безПодписи) {
  const сервер = подменныйСервер(ответы);
  const рез = поднять(исходник, {
    документ: сделатьДокумент(),
    память: сделатьПамять(false),
    telegram: безПодписи ? {} : { initData: ПОДПИСЬ },
    fetch: сервер.fetch,
    имяФайла: 'общее/js/сеть.js'
  });
  const настоящий = рез.песочница.setTimeout;
  /* Только паузу в 2 секунды между повторами делаем мгновенной — сторожа
     запросов (десятки секунд) оставляем как есть. */
  рез.песочница.setTimeout = function (дело, мс) {
    return настоящий(дело, мс === 2000 ? 0 : мс);
  };
  return { сеть: рез.окно.Сеть, сервер: сервер };
}

