'use strict';

/* =====================================================================
   ПРОФИЛЬ: мои очки по каждой игре.

   Что проверяем. Функцию server/рейтинг.js моиОчкиПоИграм(номер) —
   ту, из которой экран «Профиль» рисует блок «Ваши очки по играм».
   Она отвечает массивом [{ игра, очки, побед, партий }] по убыванию
   очков; игра без записи игрока в массив не попадает; нет ни одной
   записи — пустой массив, а не null.

   Ни сети, ни сервера здесь нет: работаем с модулем напрямую, папку
   данных уводим в свою временную (иначе первое же чтение подхватило бы
   боевые файлы владельца — см. server/папка-данных.js).

   Сценарии:
     1. Функция вообще есть и отвечает массивом.
     2. Три игры у игрока → ровно три записи, поля только игра/очки/
        побед/партий, имя игры — непустая строка.
     3. Порядок по убыванию очков: шашки (больше всех) → шахматы → дурак.
     4. Числа целые и именно числа, а не строки.
     5. Очки каждой записи равны очкам в срезе этой игры отдельно.
     6. Сумма очков (и побед, и партий) равна общему счёту «все игры»
        из срезПоВсемИграм — общая таблица там считается именно суммой
        по всем играм (см. списокПоВсемИграм в server/рейтинг.js).
     7. Игрок без единой записи → пустой МАССИВ, не null и не undefined.
     8. Наружу не уходят номера: ни свой, ни соперников, ни полей
        «номер»/«имя» в записях.

   ЛОМАЮЩИЙ ЗАПУСК (--сломать). Копируем server/рейтинг.js во временную
   папку и портим КОПИЮ — двумя способами по очереди:
     • снимаем сравнение в сортировке (порядок становится случайным
       порядком таблиц);
     • пустой ответ подменяем на null.
   Каждая ломаная копия ОБЯЗАНА покраснеть; не покраснела — это провал
   самой проверки. Настоящий файл проекта не портится никогда.

   Замена в копии должна найтись ровно один раз: ноль (строку в модуле
   переименовали) или больше одной — выход кодом 2, чтобы поломка не
   оказалась украшением.

   Запуск:
       node tests/профиль-очки-по-играм.js
       node tests/профиль-очки-по-играм.js --сломать

   Выход: 0 — всё хорошо; 1 — есть провалы (или ломаная копия НЕ
   покраснела); 2 — поломку не удалось применить ровно один раз.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

const ЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;
const КОРЕНЬ = path.join(__dirname, '..');
const ФАЙЛ_РЕЙТИНГА = path.join(КОРЕНЬ, 'server', 'рейтинг.js');

/* Данные уводим в свою временную папку ДО подключения модуля рейтинга. */
const СВОЯ_ПАПКА = fs.mkdtempSync(path.join(os.tmpdir(), 'профиль-очки-'));
process.env.GAMES_DATA = СВОЯ_ПАПКА;

/* Кто играет в этой проверке. */
const ИГРОК = 100001;          // играет в три игры
const БЕЗ_ПАРТИЙ = 100009;     // не играл вовсе
const ПЕРВЫЙ_СОПЕРНИК = 200001;
const СКОЛЬКО_СОПЕРНИКОВ = 7;  // всем партиям хватает разных соперников

/* Сколько побед даём в каждой игре. Числа разные нарочно: порядок по
   убыванию очков (шашки → шахматы → дурак) НЕ совпадает с порядком, в
   котором игры ложатся в память (дурак → шашки → шахматы). Иначе
   снятое сравнение в сортировке прошло бы незамеченным. */
const ПОБЕД_В_ИГРЕ = [
  { игра: 'дурак', побед: 1 },
  { игра: 'шашки', побед: 4 },
  { игра: 'шахматы', побед: 2 }
];

/* Ожидаемый порядок ответа: больше очков — выше. */
const ОЖИДАЕМЫЙ_ПОРЯДОК = ['шашки', 'шахматы', 'дурак'];

/* =====================================================================
   Счёт проверок
   ===================================================================== */

/** Копилка одного прогона: сколько проверок и какие покраснели. */
function создатьКопилку(молча) {
  return { проверок: 0, провалы: [], молча: молча === true };
}

function проверить(копилка, условие, что) {
  копилка.проверок++;
  if (!условие) {
    копилка.провалы.push(что);
    if (!копилка.молча) console.log('  ✗ ' + что);
  } else if (!копилка.молча) {
    console.log('  ✓ ' + что);
  }
}

/* =====================================================================
   Засев данных
   ===================================================================== */

/** Партия «победил наш игрок», соперник — каждый раз новый человек. */
function сыгратьПобеду(рейтинг, игра, номерСоперника) {
  рейтинг.учестьПартию(игра, [
    { номер: ИГРОК, имя: 'Тестовик', этоБот: false, победил: true, ничья: false },
    { номер: номерСоперника, имя: 'Соперник', этоБот: false, победил: false, ничья: false }
  ]);
}

function засеять(рейтинг) {
  рейтинг.забытьВсё();
  рейтинг.включитьЗапись();

  let следующийСоперник = ПЕРВЫЙ_СОПЕРНИК;
  for (const что of ПОБЕД_В_ИГРЕ) {
    for (let раз = 0; раз < что.побед; раз++) {
      /* Соперники разные: с одним и тем же человеком в зачёт идут
         только первые пять партий в сутки (ограничитель сговора). */
      сыгратьПобеду(рейтинг, что.игра, следующийСоперник);
      следующийСоперник++;
    }
  }
}

/* =====================================================================
   Сценарии
   ===================================================================== */

function прогнать(рейтинг, копилка) {
  if (typeof рейтинг.моиОчкиПоИграм !== 'function') {
    проверить(копилка, false, 'модуль отдаёт наружу моиОчкиПоИграм');
    return;
  }
  проверить(копилка, true, 'модуль отдаёт наружу моиОчкиПоИграм');

  засеять(рейтинг);
  const поИграм = рейтинг.моиОчкиПоИграм(ИГРОК);

  /* 1. Ответ — массив. Дальше без него смотреть нечего. */
  проверить(копилка, Array.isArray(поИграм),
    'ответ — массив, получили: ' + Object.prototype.toString.call(поИграм));
  if (!Array.isArray(поИграм)) return;

  /* 2. Три игры — три записи с ожидаемым набором полей. */
  проверить(копилка, поИграм.length === ПОБЕД_В_ИГРЕ.length,
    'записей столько же, сколько игр: ожидали ' + ПОБЕД_В_ИГРЕ.length +
    ', получили ' + поИграм.length);

  const ЖДЁМ_ПОЛЯ = ['игра', 'очки', 'побед', 'партий'].sort().join(',');
  for (const запись of поИграм) {
    const поля = Object.keys(запись).sort().join(',');
    проверить(копилка, поля === ЖДЁМ_ПОЛЯ,
      'поля записи только игра/очки/побед/партий — у «' + запись.игра + '»: ' + поля);
  }

  /* 3. Порядок по убыванию очков. */
  const порядокИмён = поИграм.map(function (запись) { return запись.игра; });
  проверить(копилка, порядокИмён.join(',') === ОЖИДАЕМЫЙ_ПОРЯДОК.join(','),
    'порядок по убыванию очков: ожидали ' + ОЖИДАЕМЫЙ_ПОРЯДОК.join(' → ') +
    ', получили ' + порядокИмён.join(' → '));

  let очкиНеРастут = true;
  for (let место = 1; место < поИграм.length; место++) {
    if (поИграм[место].очки > поИграм[место - 1].очки) очкиНеРастут = false;
  }
  проверить(копилка, очкиНеРастут,
    'очки в ответе не растут сверху вниз: ' +
    поИграм.map(function (з) { return з.игра + ' ' + з.очки; }).join(', '));

  /* 4. Числа целые и это числа, а не строки. */
  for (const запись of поИграм) {
    const целые = Number.isInteger(запись.очки) &&
      Number.isInteger(запись.побед) && Number.isInteger(запись.партий);
    проверить(копилка, целые,
      'числа целые у «' + запись.игра + '»: очки ' + JSON.stringify(запись.очки) +
      ', побед ' + JSON.stringify(запись.побед) + ', партий ' + JSON.stringify(запись.партий));
    проверить(копилка, typeof запись.игра === 'string' && запись.игра.length > 0,
      'имя игры — непустая строка: ' + JSON.stringify(запись.игра));
  }

  /* 5. Очки записи = очкам в срезе этой игры отдельно. */
  for (const что of ПОБЕД_В_ИГРЕ) {
    const срезИгры = рейтинг.срезДляИгрока(что.игра, ИГРОК);
    const запись = поИграм.find(function (з) { return з.игра === что.игра; });
    проверить(копилка, !!запись, 'игра «' + что.игра + '» есть в ответе');
    if (!запись || !срезИгры.я) continue;
    проверить(копилка, запись.очки === срезИгры.я.очки,
      'очки «' + что.игра + '»: в ответе ' + запись.очки + ', в срезе игры ' + срезИгры.я.очки);
    проверить(копилка, запись.побед === срезИгры.я.побед,
      'победы «' + что.игра + '»: в ответе ' + запись.побед + ', в срезе игры ' + срезИгры.я.побед);
    проверить(копилка, запись.партий === срезИгры.я.партий,
      'партии «' + что.игра + '»: в ответе ' + запись.партий + ', в срезе игры ' + срезИгры.я.партий);
  }

  /* 6. Сумма = общий счёт «все игры» (там именно сумма по играм). */
  const суммаОчков = поИграм.reduce(function (итог, з) { return итог + з.очки; }, 0);
  const суммаПобед = поИграм.reduce(function (итог, з) { return итог + з.побед; }, 0);
  const суммаПартий = поИграм.reduce(function (итог, з) { return итог + з.партий; }, 0);
  const срезВсе = рейтинг.срезПоВсемИграм(ИГРОК);

  проверить(копилка, !!(срезВсе && срезВсе.я), 'общий срез «все игры» нашёл игрока');
  if (срезВсе && срезВсе.я) {
    проверить(копилка, суммаОчков === срезВсе.я.очки,
      'сумма очков по играм = очкам в «все игры»: ' + суммаОчков + ' и ' + срезВсе.я.очки);
    проверить(копилка, суммаПобед === срезВсе.я.побед,
      'сумма побед = победам в «все игры»: ' + суммаПобед + ' и ' + срезВсе.я.побед);
    проверить(копилка, суммаПартий === срезВсе.я.партий,
      'сумма партий = партиям в «все игры»: ' + суммаПартий + ' и ' + срезВсе.я.партий);
  }

  /* 7. Игрок без записей: пустой массив, не null. */
  const пусто = рейтинг.моиОчкиПоИграм(БЕЗ_ПАРТИЙ);
  проверить(копилка, пусто !== null && пусто !== undefined,
    'у игрока без партий ответ не null и не undefined, получили: ' + JSON.stringify(пусто));
  проверить(копилка, Array.isArray(пусто),
    'у игрока без партий ответ — массив: ' + Object.prototype.toString.call(пусто));
  проверить(копилка, Array.isArray(пусто) && пусто.length === 0,
    'у игрока без партий массив пустой, длина: ' + (Array.isArray(пусто) ? пусто.length : 'нет'));

  /* 8. Номера наружу не уходят. */
  const какТекст = JSON.stringify(поИграм);
  проверить(копилка, какТекст.indexOf(String(ИГРОК)) === -1,
    'свой номер игрока не встречается в ответе');
  let чужихНет = true;
  for (let сдвиг = 0; сдвиг < СКОЛЬКО_СОПЕРНИКОВ; сдвиг++) {
    if (какТекст.indexOf(String(ПЕРВЫЙ_СОПЕРНИК + сдвиг)) !== -1) чужихНет = false;
  }
  проверить(копилка, чужихНет, 'номера соперников не встречаются в ответе');
  let лишнихПолейНет = true;
  for (const запись of поИграм) {
    if ('номер' in запись || 'имя' in запись) лишнихПолейНет = false;
  }
  проверить(копилка, лишнихПолейНет, 'в записях нет полей «номер» и «имя»');
}

/* =====================================================================
   Обычный прогон
   ===================================================================== */

function прогнатьСОригиналом() {
  console.log('=== Профиль: мои очки по играм (настоящий server/рейтинг.js) ===');
  const копилка = создатьКопилку(false);
  try {
    const рейтинг = require(ФАЙЛ_РЕЙТИНГА);
    прогнать(рейтинг, копилка);
  } catch (беда) {
    копилка.провалы.push('проверка оборвалась: ' + беда.message);
    console.log('ПРОВЕРКА ОБОРВАЛАСЬ: ' + беда.message);
    console.log(беда.stack);
  }
  return копилка;
}

/* =====================================================================
   Ломающий запуск: портим КОПИЮ файла, не файл проекта
   ===================================================================== */

/**
 * Сделать испорченную копию server/рейтинг.js во временной папке.
 * Замена обязана найтись ровно один раз — иначе выходим кодом 2:
 * ноль найденного означает, что модуль перестроили, и поломка стала
 * украшением, а не проверкой.
 */
function испортитьКопию(название, что, чем) {
  const папкаКопии = fs.mkdtempSync(path.join(os.tmpdir(), 'профиль-очки-копия-'));
  const текст = fs.readFileSync(ФАЙЛ_РЕЙТИНГА, 'utf8');

  const сколькоРаз = текст.split(что).length - 1;
  if (сколькоРаз !== 1) {
    console.log('ПОЛОМКА НЕ ПРИМЕНИЛАСЬ («' + название + '»): строка ' +
      JSON.stringify(что) + ' найдена ' + сколькоРаз + ' раз(а) вместо одного.');
    console.log('Похоже, server/рейтинг.js перестроили — поправьте проверку тем же коммитом.');
    process.exit(2);
  }

  /* Относительные require копия не найдёт — распрямляем их в полные пути. */
  let сломанное = текст.replace(что, чем);
  for (const сосед of ['./игры/умолчания.js', './сила-игроков.js', './папка-данных.js']) {
    const полный = path.join(КОРЕНЬ, 'server', сосед.slice(2)).replace(/\\/g, '\\\\');
    сломанное = сломанное.replace("require('" + сосед + "')", "require('" + полный + "')");
  }

  const файлКопии = path.join(папкаКопии, 'рейтинг.js');
  fs.writeFileSync(файлКопии, сломанное, 'utf8');
  return { папка: папкаКопии, файл: файлКопии };
}

/** Прогнать те же сценарии на испорченной копии: она обязана покраснеть. */
function потребоватьПровала(название, что, чем, общая) {
  const копия = испортитьКопию(название, что, чем);
  const своиДанные = path.join(копия.папка, 'данные');
  fs.mkdirSync(своиДанные, { recursive: true });
  process.env.GAMES_DATA = своиДанные;

  /* Сила игроков держит свою память — копии нужна чистая. */
  delete require.cache[require.resolve(path.join(КОРЕНЬ, 'server', 'сила-игроков.js'))];

  const копилка = создатьКопилку(true);
  try {
    прогнать(require(копия.файл), копилка);
  } catch (беда) {
    копилка.провалы.push('копия упала: ' + беда.message);
  } finally {
    delete require.cache[копия.файл];
    delete require.cache[require.resolve(path.join(КОРЕНЬ, 'server', 'сила-игроков.js'))];
    try { fs.rmSync(копия.папка, { recursive: true, force: true }); } catch (е) { /* нарочно молчим */ }
    process.env.GAMES_DATA = СВОЯ_ПАПКА;
  }

  console.log('\nЛоманая копия «' + название + '»: покраснело проверок ' +
    копилка.провалы.length + ' из ' + копилка.проверок);
  for (const беда of копилка.провалы.slice(0, 3)) console.log('  ✗ ' + беда);

  проверить(общая, копилка.провалы.length > 0,
    'ломаная копия «' + название + '» замечена проверкой');
}

/* =====================================================================
   Главный запуск
   ===================================================================== */

(function () {
  const общая = прогнатьСОригиналом();

  if (ЛОМАТЬ) {
    console.log('\n=== Ломающий запуск: портим КОПИИ во временной папке ===');
    /* Поломка 1: снято сравнение в сортировке — порядок становится
       порядком таблиц в памяти (дурак, шашки, шахматы). */
    потребоватьПровала('снята сортировка',
      'поИграм.sort(function (а, б) { return б.очки - а.очки; });',
      'поИграм.sort(function () { return 0; });',
      общая);
    /* Поломка 2: пустой ответ подменён на null. */
    потребоватьПровала('пусто вместо массива → null',
      'return поИграм;',
      'return поИграм.length ? поИграм : null;',
      общая);
  }

  try { fs.rmSync(СВОЯ_ПАПКА, { recursive: true, force: true }); } catch (е) { /* нарочно молчим */ }

  console.log('\n----------------------------------------');
  for (const беда of общая.провалы) console.log('  - ' + беда);
  console.log('Итого проверок: ' + общая.проверок + ', провалов: ' + общая.провалы.length);
  process.exit(общая.провалы.length > 0 ? 1 : 0);
})();
