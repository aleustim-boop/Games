'use strict';

/* Проверка серии дней подряд (Рейтинг.отметитьДень / Рейтинг.серияДней).
   js/telegram.js запускается в поддельном браузере с ПОДДЕЛЬНЫМИ ЧАСАМИ:
   «сейчас» переставляется вручную, чтобы прожить неделю за секунду. */

/* Поддельный браузер — общий (tests/поддельный-браузер.js): память, облако
   с правилом латиницы и выключателем, часы, которые переставляют рукой. */
const браузер = require('./поддельный-браузер.js');

const беды = [];
let проверок = 0;
function проверить(условие, что) { проверок++; if (!условие) { беды.push(что); console.log('  ПЛОХО: ' + что); } else { console.log('  ок: ' + что); } }

/* Часы, которые переставляются рукой. Файл зовёт new Date(), Date.now(), Date.UTC, new Date(число). */
// 1 сентября 2026, полдень по местному
const часы = браузер.поддельныеЧасы(new Date(2026, 8, 1, 12, 0).getTime());
function поставитьЧасы(год, месяц, день, час, минута) { часы.поставить(год, месяц, день, час || 12, минута || 0); }

const сделатьПамять = () => браузер.сделатьПамять(false);
/* Облако по правилу латиницы, считает записи; «выключено» — отвечает ошибкой. */
const сделатьОблако = () => браузер.сделатьОблако();

function завести(память, облако) {
  const х = браузер.поднятьTelegramJS({ память, облако, часы });
  return { Р: х.Рейтинг, память, облако };
}

const тихо = () => new Promise(р => setTimeout(р, 5));   // дать досылке в облако дойти
const кратко = (с) => `серия ${с.серия}, лучшая ${с.лучшая}, отмечен ${с.сегодняОтмечен ? 'да' : 'нет'}, впервые ${с.сегодняВпервые ? 'да' : 'нет'}`;

(async () => {
  console.log('=== 1. Первая отметка и повтор в тот же день ===');
  {
    const х = завести(сделатьПамять(), null);
    поставитьЧасы(2026, 9, 1, 12, 0);
    const а = await х.Р.отметитьДень();
    const б = await х.Р.отметитьДень();
    console.log('  первая: ' + кратко(а) + '; вторая: ' + кратко(б));
    проверить(а.серия === 1 && а.лучшая === 1 && а.сегодняОтмечен && а.сегодняВпервые, 'первая партия дня: серия 1, впервые');
    проверить(б.серия === 1 && б.лучшая === 1 && б.сегодняОтмечен && !б.сегодняВпервые, 'вторая партия того же дня серию не растит');
    проверить(Object.keys(х.память.ящик).join() === 'days_streak', 'в памяти один ключ days_streak');
  }

  console.log('=== 2. Вчера в 23:50 и сегодня в 00:10 — два дня подряд ===');
  {
    const х = завести(сделатьПамять(), null);
    поставитьЧасы(2026, 9, 1, 23, 50);
    await х.Р.отметитьДень();
    поставитьЧасы(2026, 9, 2, 0, 10);
    const с = await х.Р.отметитьДень();
    console.log('  ' + кратко(с));
    проверить(с.серия === 2 && с.сегодняВпервые, 'серия 2');
  }

  console.log('=== 3. Вчера играл, сегодня нет, завтра играл — серия 1, лучшая уцелела ===');
  {
    const х = завести(сделатьПамять(), null);
    поставитьЧасы(2026, 9, 1); await х.Р.отметитьДень();
    поставитьЧасы(2026, 9, 2); await х.Р.отметитьДень();
    поставитьЧасы(2026, 9, 3); const д3 = await х.Р.отметитьДень();
    поставитьЧасы(2026, 9, 5); const д5 = await х.Р.отметитьДень();
    console.log('  3 сентября: ' + кратко(д3) + '; 5 сентября (4-е пропущено): ' + кратко(д5));
    проверить(д3.серия === 3 && д3.лучшая === 3, 'три дня подряд — серия 3');
    проверить(д5.серия === 1 && д5.лучшая === 3 && д5.сегодняВпервые, 'после пропуска серия 1, лучшая 3');
  }

  console.log('=== 4. Чтение без отметки: под угрозой, оборвана, месяц спустя ===');
  {
    const х = завести(сделатьПамять(), null);
    поставитьЧасы(2026, 9, 1); await х.Р.отметитьДень();
    поставитьЧасы(2026, 9, 2); await х.Р.отметитьДень();
    поставитьЧасы(2026, 9, 2, 20); const тотЖеДень = await х.Р.серияДней();
    поставитьЧасы(2026, 9, 3, 9); const утроСледующего = await х.Р.серияДней();
    поставитьЧасы(2026, 9, 4); const черезДень = await х.Р.серияДней();
    поставитьЧасы(2026, 10, 15); const черезМесяц = await х.Р.серияДней();
    console.log('  тот же день: ' + кратко(тотЖеДень));
    console.log('  утро следующего: ' + кратко(утроСледующего));
    console.log('  через день: ' + кратко(черезДень));
    console.log('  через месяц: ' + кратко(черезМесяц));
    проверить(тотЖеДень.серия === 2 && тотЖеДень.сегодняОтмечен && !тотЖеДень.сегодняВпервые, 'в день отметки: серия 2, отмечен, впервые — нет');
    проверить(утроСледующего.серия === 2 && !утроСледующего.сегодняОтмечен, 'наутро серия жива (2) и не отмечена — «под угрозой»');
    проверить(черезДень.серия === 0 && черезДень.лучшая === 2, 'пропущен день — серия 0, лучшая 2');
    проверить(черезМесяц.серия === 0 && черезМесяц.лучшая === 2, 'через месяц то же');
    проверить(JSON.parse(х.память.ящик.days_streak).серия === 2, 'чтение хранилище не меняет: в записи по-прежнему 2');
    const после = await х.Р.отметитьДень();
    проверить(после.серия === 1 && после.лучшая === 2, 'отметка через месяц начинает серию заново с 1');
  }

  console.log('=== 5. Сведение облака и памяти: отрезки дней ===');
  {
    const день = (г, м, д) => { поставитьЧасы(г, м, д); return Math.floor((Date.UTC(г, м - 1, д) - Date.UTC(2020, 0, 1)) / 86400000); };
    const запись = (день, серия, лучшая) => JSON.stringify({ версия: 1, день, серия, лучшая });
    async function свести(облачная, местная, г, м, д) {
      const облако = сделатьОблако();
      if (облачная) облако.ящик.days_streak = запись(...облачная);
      const память = сделатьПамять();
      if (местная) память.setItem('days_streak', запись(...местная));
      const х = завести(память, облако);
      поставитьЧасы(г, м, д);
      const с = await х.Р.серияДней();
      await тихо();
      return { с, облако };
    }
    const Д = день(2026, 9, 11);   // «сегодня» = 11 сентября; Д-1 = вчера, Д-10 = 1 сентября
    let r;
    r = await свести([Д - 1, 10, 10], [Д, 1, 1], 2026, 9, 11);
    console.log('  облако: 10 дней до вчера; память: 1 день сегодня → ' + кратко(r.с));
    проверить(r.с.серия === 11 && r.с.лучшая === 11, 'соприкасаются — одна полоса, 11 (не 10 и не 1)');
    r = await свести([Д - 11, 10, 10], [Д, 2, 2], 2026, 9, 11);
    console.log('  облако: 10 дней, оборвалось 11 дней назад; память: 2 дня → ' + кратко(r.с));
    проверить(r.с.серия === 2 && r.с.лучшая === 10, 'не соприкасаются — живая двойка, лучшая 10');
    r = await свести([Д, 10, 10], [Д, 3, 3], 2026, 9, 11);
    console.log('  оба сегодня: облако 10, память 3 → ' + кратко(r.с));
    проверить(r.с.серия === 10, 'один день на двух устройствах — не складываем, берём длинную (10)');
    r = await свести([Д, 5, 5], [Д, 5, 5], 2026, 9, 11);
    проверить(r.с.серия === 5, 'одинаковые записи — 5, а не 10');
    r = await свести([Д - 2, 10, 10], [Д, 2, 2], 2026, 9, 11);
    console.log('  облако: 10 дней до позавчера; память: вчера и сегодня → ' + кратко(r.с));
    проверить(r.с.серия === 12, 'полоса без дыры: 12');
    r = await свести([Д - 3, 10, 10], [Д, 2, 2], 2026, 9, 11);
    console.log('  облако: 10 дней до 3 дней назад; память: вчера и сегодня → ' + кратко(r.с));
    проверить(r.с.серия === 2 && r.с.лучшая === 10, 'дыра в один день рвёт полосу: 2');
    r = await свести([Д - 1, 3, 3], [Д, 10, 10], 2026, 9, 11);
    проверить(r.с.серия === 10, 'память уже включает облачные дни: 10, не 13');
    r = await свести(null, [Д, 4, 4], 2026, 9, 11);
    проверить(r.с.серия === 4 && r.облако.ящик.days_streak !== undefined, 'облако пустое — досылаем туда местное');
    r = await свести([Д, 4, 4], null, 2026, 9, 11);
    проверить(r.с.серия === 4, 'память пустая — берём облачное');
  }

  console.log('=== 6. Два устройства через облако ===');
  {
    const облако = сделатьОблако();
    const телефон = завести(сделатьПамять(), облако);
    поставитьЧасы(2026, 9, 1); await телефон.Р.отметитьДень();
    поставитьЧасы(2026, 9, 2); await телефон.Р.отметитьДень();
    поставитьЧасы(2026, 9, 3); const т3 = await телефон.Р.отметитьДень();
    const планшет = завести(сделатьПамять(), облако);
    поставитьЧасы(2026, 9, 4); const п4 = await планшет.Р.отметитьДень();
    поставитьЧасы(2026, 9, 5); const т5 = await телефон.Р.отметитьДень();
    const п5 = await планшет.Р.серияДней();
    console.log('  телефон 3.09: ' + кратко(т3) + '; планшет 4.09: ' + кратко(п4) + '; телефон 5.09: ' + кратко(т5) + '; планшет читает: ' + кратко(п5));
    проверить(п4.серия === 4, 'планшет продолжил серию телефона: 4');
    проверить(т5.серия === 5, 'телефон продолжил серию планшета: 5');
    проверить(п5.серия === 5 && п5.сегодняОтмечен, 'планшет видит 5 и «сегодня отмечено»');
    проверить(облако.отказы.length === 0, 'облако ни разу не отказало по ключу');
  }

  console.log('=== 7. Досылка не долбится: повторное чтение облако не переписывает ===');
  {
    const облако = сделатьОблако();
    const память = сделатьПамять();
    const без = завести(память, null);
    поставитьЧасы(2026, 9, 1); await без.Р.отметитьДень();
    поставитьЧасы(2026, 9, 2); await без.Р.отметитьДень();
    const с = завести(память, облако);
    await с.Р.серияДней(); await тихо();
    const после1 = облако.записей;
    await с.Р.серияДней(); await тихо();
    await с.Р.серияДней(); await тихо();
    console.log('  записей в облако после первого чтения: ' + после1 + ', после трёх: ' + облако.записей);
    проверить(после1 === 1, 'первое чтение дослало запись (1)');
    проверить(облако.записей === 1, 'дальше облако не трогали');
  }

  console.log('=== 8. Отметка из будущего (часы сбились или другой пояс) серию не рвёт ===');
  {
    const память = сделатьПамять();
    const х = завести(память, null);
    поставитьЧасы(2026, 9, 5); await х.Р.отметитьДень();
    поставитьЧасы(2026, 9, 6); await х.Р.отметитьДень();
    поставитьЧасы(2026, 9, 5, 23); const назад = await х.Р.отметитьДень();
    const чтение = await х.Р.серияДней();
    console.log('  часы отстали на день: ' + кратко(назад));
    проверить(назад.серия === 2 && !назад.сегодняВпервые && назад.сегодняОтмечен, 'серия 2 цела, отметка не первая');
    проверить(чтение.серия === 2 && чтение.сегодняОтмечен, 'чтение: серия жива, сегодня отмечено');
    проверить(JSON.parse(память.ящик.days_streak).серия === 2, 'запись не тронута');
  }

  console.log('=== 9. Мусор и чужая версия в хранилище — нули, потом честная единица ===');
  {
    for (const текст of ['мусор', '{"версия":2,"день":2400,"серия":9,"лучшая":9}', '{"версия":1,"день":"abc","серия":-3}', '[]', '']) {
      const память = сделатьПамять(); память.setItem('days_streak', текст);
      const х = завести(память, null);
      поставитьЧасы(2026, 9, 7);
      const ч = await х.Р.серияДней();
      const о = await х.Р.отметитьДень();
      проверить(ч.серия === 0 && ч.лучшая === 0 && о.серия === 1 && о.лучшая === 1 && о.сегодняВпервые, 'текст «' + текст.slice(0, 25) + '» → нули, отметка даёт 1');
    }
  }

  console.log('=== 10. Хранилища нет вовсе — обещание не падает ===');
  {
    const сломанная = { getItem() { throw new Error('нельзя'); }, setItem() { throw new Error('нельзя'); }, removeItem() { throw new Error('нельзя'); } };
    const х = завести(сломанная, null);
    поставитьЧасы(2026, 9, 7);
    const о = await х.Р.отметитьДень();
    const ч = await х.Р.серияДней();
    console.log('  отметка: ' + кратко(о) + '; чтение: ' + кратко(ч));
    проверить(о.серия === 1 && о.сегодняВпервые, 'отметка отвечает единицей, не падает');
    проверить(ч.серия === 0, 'чтение отвечает нулём, не падает');
    проверить(х.Р.готов() === false, 'готов() честно говорит «нет»');
  }

  console.log('=== 11. Очистка рейтинга серию дней не трогает; рекорды и рейтинг соседям не мешают ===');
  {
    const х = завести(сделатьПамять(), null);
    поставитьЧасы(2026, 9, 1); await х.Р.отметитьДень();
    поставитьЧасы(2026, 9, 2); await х.Р.отметитьДень();
    await х.Р.записатьПартию({ исход: 'победа', подпись: 'обычный', игра: 'шашки' });
    await х.Р.очистить('дурак'); await х.Р.очистить('шашки');
    const с = await х.Р.серияДней();
    console.log('  ключи: [' + Object.keys(х.память.ящик).sort().join(', ') + '], серия: ' + кратко(с));
    проверить(с.серия === 2, 'после очистки рейтинга серия дней всё ещё 2');
    проверить(Object.keys(х.память.ящик).sort().join(', ') === 'days_streak, rating_durak, rating_shashki', 'серия дней лежит своим ключом рядом с рейтингом');
  }

  console.log('=== 12. записатьПартию отмечает день сама и приносит сводку серии дней ===');
  {
    const облако = сделатьОблако();
    const х = завести(сделатьПамять(), облако);
    поставитьЧасы(2026, 9, 1);
    const п1 = await х.Р.записатьПартию({ исход: 'победа', подпись: 'обычный' });
    const п2 = await х.Р.записатьПартию({ исход: 'поражение', подпись: 'сложный', игра: 'шашки' });
    поставитьЧасы(2026, 9, 2);
    const п3 = await х.Р.записатьПартию({ исход: 'ничья', подпись: 'лёгкий', соперники: 'люди' });
    const мусор = await х.Р.записатьПартию({ исход: 'непонятно', подпись: 'обычный' });
    const без = await х.Р.записатьПартию(null);
    const чтение = await х.Р.серияДней();
    const рейтинг = await х.Р.прочитать('дурак');
    console.log('  1.09 победа: ' + кратко(п1.серияДней) + '; 1.09 шашки: ' + кратко(п2.серияДней) + '; 2.09 сеть: ' + кратко(п3.серияДней));
    console.log('  ключи: [' + Object.keys(х.память.ящик).sort().join(', ') + '], в облаке: [' + Object.keys(облако.ящик).sort().join(', ') + ']');
    проверить(п1.серияДней && п1.серияДней.серия === 1 && п1.серияДней.сегодняВпервые, 'первая партия дня отметила день: серия 1, впервые');
    проверить(п2.серияДней.серия === 1 && !п2.серияДней.сегодняВпервые, 'вторая партия того же дня (шашки) серию не растит');
    проверить(п3.серияДней.серия === 2 && п3.серияДней.сегодняВпервые, 'ничья по сети назавтра растит серию дней: 2');
    проверить(мусор.серияДней === undefined, 'партия с неразобранным исходом день не отмечает и поля не несёт');
    проверить(без.серияДней === undefined, 'пустое описание — тоже');
    проверить(чтение.серия === 2 && чтение.сегодняОтмечен, 'серияДней() видит те же 2');
    проверить(рейтинг.серияДней === undefined, 'у прочитать() поля серияДней нет');
    проверить(п1.всего.партий === 1 && п3.всего.партий === 2, 'счёт партий дурака при этом верный: 1, потом 2');
    проверить(Object.keys(облако.ящик).sort().join(', ') === 'days_streak, rating_durak, rating_shashki', 'в облаке три записи под латинскими ключами');
    проверить(облако.отказы.length === 0, 'облако не отказывало');
  }

  console.log('=== 13. Партия без облака и с мёртвой памятью — обещание не падает, сводка на месте ===');
  {
    const сломанная = { getItem() { throw new Error('нельзя'); }, setItem() { throw new Error('нельзя'); }, removeItem() { throw new Error('нельзя'); } };
    const х = завести(сломанная, null);
    поставитьЧасы(2026, 9, 3);
    const п = await х.Р.записатьПартию({ исход: 'победа', подпись: 'обычный' });
    проверить(п.всего.партий === 1 && п.серияДней && п.серияДней.серия === 1, 'сводка партии и серии дней пришли, ничего не упало');
  }

  console.log('\nпроверок сделано: ' + проверок);
  if (беды.length) { console.log('=== ИТОГ: ЕСТЬ БЕДЫ (' + беды.length + ') ==='); беды.forEach(б => console.log('  - ' + б)); process.exit(1); }
  console.log('=== ИТОГ: серия дней считается правильно ===');
})();
