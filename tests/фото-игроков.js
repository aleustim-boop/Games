function сделатьСломаннуюКопию(поломка) {
  const оригТекст = fs.readFileSync(ИСХОДНИК, 'utf8');
  const сломанныйТекст = оригТекст.replace(поломка.откуда, поломка.куда);
  if (сломанныйТекст === оригТекст) {
    return { ошибка: 'поломка "' + поломка.имя + '" не применилась: не найден фрагмент ' + JSON.stringify(поломка.откуда) };
  }
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'фото-игроков-сломать-'));
  временныеПапки.push(папка);
  const файл = path.join(папка, 'фото-игроков.js');
  fs.writeFileSync(файл, сломанныйТекст, 'utf8');
  return { путь: файл };
}

function прибратьВременныеПапки() {
  for (const папка of временныеПапки) {
    try { fs.rmSync(папка, { recursive: true, force: true }); } catch (е) { /* временная папка, не страшно */ }
  }
}

async function основной() {
  console.log('=== Проверка server/фото-игроков.js ===');
  let итогКод = 0;

  try {
    if (!СЛОМАТЬ) {
      console.log('\n--- Обычный прогон ---');
      const прогон = новыйПрогон();
      await прогонВсехСценариев(require(ИСХОДНИК).создать, прогон);

      console.log('\nИтого проверок: ' + прогон.счёт() + ', провалов: ' + прогон.провалы.length);
      for (const беда of прогон.провалы) console.log('  - ' + беда);
      итогКод = прогон.провалы.length > 0 ? 1 : 0;
    } else {
      console.log('\n*** ЛОМАЮЩИЙ ЗАПУСК: по одной копии модуля на каждую поломку ***');
      for (const поломка of ПОЛОМКИ) {
        console.log('\n--- Копия ' + поломка.имя + ' ---');
        const копия = сделатьСломаннуюКопию(поломка);
        if (копия.ошибка) {
          console.log('  ✗ ' + копия.ошибка);
          итогКод = 1;
          continue;
        }
        const прогон = новыйПрогон();
        await прогонВсехСценариев(require(копия.путь).создать, прогон);
        const непойманные = поломка.ожидаемые.filter(function (н) { return !(н in прогон.провалыПоСценариям); });
        if (непойманные.length > 0) {
          console.log('  ПРОВЕРКА СЛЕПАЯ: копия ' + поломка.имя + ' не покраснела в сценариях ' + непойманные.join(', '));
          итогКод = 1;
        } else {
          console.log('  копия ' + поломка.имя + ' покраснела как положено в сценариях ' +
            поломка.ожидаемые.join(', ') + ' — проверка рабочая');
        }
      }
      console.log('\nЛомающий запуск завершён, итоговый код: ' + итогКод +
        ' (0 — все поломки честно поймали красноту; 1 — где-то проверка слепая)');
    }
  } finally {
    прибратьВременныеПапки();
  }

  process.exit(итогКод);
}

основной().catch(function (беда) {
  console.log('ПРОВЕРКА ОБОРВАЛАСЬ: ' + беда.message);
  console.log(беда.stack);
  прибратьВременныеПапки();
  process.exit(1);
});
