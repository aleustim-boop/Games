'use strict';

/* Проверка довода «игра» у saveScore/loadScore.
   Запускает js/telegram.js в поддельном браузере (как штатные проверки в tests/)
   и сравнивает: дурак без довода — ровно как в файле из последнего коммита;
   шашки — своя таблица; незнакомая игра — ключ из числа и одно предупреждение. */

const fs = require('fs');
const path = require('path');
/* Поддельный браузер — общий для всех проверок без браузера (tests/поддельный-браузер.js):
   память, облако с правилом латиницы, песочница. Своей копии здесь больше нет. */
const браузер = require('./поддельный-браузер.js');

const НОВЫЙ = fs.readFileSync(path.join(браузер.КОРЕНЬ, 'js', 'telegram.js'), 'utf8');
/* Файл ДО довода «игра» — из истории git, а не копией рядом: коммит 20fdaf8 —
   последний, где saveScore/loadScore про игру не знали. */
const СТАРЫЙ = браузер.исходникИзКоммита('20fdaf8', 'js/telegram.js');

const беды = [];
let проверок = 0;
function проверить(условие, что) { проверок++; if (!условие) { беды.push(что); console.log('  ПЛОХО: ' + что); } else { console.log('  ок: ' + что); } }

const сделатьПамять = () => браузер.сделатьПамять(false);
const сделатьОблако = () => браузер.сделатьОблако();   // придирчиво к имени записи, как настоящее

function завести(исходник, память, облако, предупреждения) {
  const консоль = { log() {}, warn(с) { if (предупреждения) предупреждения.push(String(с)); }, error() {} };
  const х = браузер.поднятьTelegramJS({ исходник, память, облако, консоль });
  return { saveScore: х.saveScore, loadScore: х.loadScore, isReady: х.isReady, память, облако };
}

const таблицей = (р) => р.таблица.map(с => с.очки + ' ' + с.сложность).join(' | ');
const ключиПамяти = (память) => Object.keys(память.ящик).sort().join(', ');

/* Один и тот же сценарий дурака — на старом и новом файле. */
async function сценарийДурака(исходник) {
  const память = сделатьПамять();
  память.setItem('подкидной-дурак:рекорды', JSON.stringify({ лучший: 7, таблица: [
    { очки: 7, дата: '01.09.2026', сложность: 'сложный' },
    { очки: 3, дата: '02.09.2026', сложность: 'лёгкий' }
  ] }));
  const х = завести(исходник, память, null);
  await х.saveScore(1, 'обычный');
  await х.saveScore(2, 'обычный');
  await х.saveScore(1, 'сложный · вчетвером');
  await х.saveScore(2, 'лёгкий · вчетвером');
  await х.saveScore(5);
  const р = await х.loadScore();
  return { ключи: ключиПамяти(память), таблица: таблицей(р), лучший: р.лучший, готов: х.isReady() };
}

(async () => {
  console.log('=== 1. Дурак без довода: старый файл и новый дают одно и то же ===');
  const до = await сценарийДурака(СТАРЫЙ);
  const после = await сценарийДурака(НОВЫЙ);
  console.log('  до:    ключи [' + до.ключи + '], таблица: ' + до.таблица + ', лучший ' + до.лучший);
  console.log('  после: ключи [' + после.ключи + '], таблица: ' + после.таблица + ', лучший ' + после.лучший);
  проверить(до.ключи === после.ключи, 'набор ключей в памяти совпал');
  проверить(до.таблица === после.таблица, 'таблица рекордов совпала строка в строку');
  проверить(до.лучший === после.лучший, 'лучший результат совпал');
  проверить(до.готов === после.готов, 'isReady совпал');
  проверить(после.ключи === 'records_durak, подкидной-дурак:рекорды', 'записано только в records_durak, старый ключ цел');

  console.log('=== 2. Шашки: своя таблица, старый дураков ключ не подмешивается ===');
  {
    const память = сделатьПамять();
    память.setItem('подкидной-дурак:рекорды', JSON.stringify({ лучший: 7, таблица: [{ очки: 7, дата: '01.09.2026', сложность: 'сложный' }] }));
    const х = завести(НОВЫЙ, память, null);
    await х.saveScore(1, 'обычный');            // дурак
    await х.saveScore(1, 'лёгкий', 'шашки');
    await х.saveScore(2, 'лёгкий', 'шашки');
    const шашки = await х.loadScore('шашки');
    const дурак = await х.loadScore();
    console.log('  шашки: ' + таблицей(шашки) + '  |  дурак: ' + таблицей(дурак));
    console.log('  ключи: [' + ключиПамяти(память) + ']');
    проверить(таблицей(шашки) === '2 лёгкий', 'у шашек одна строка своей серии, дураковых записей нет');
    проверить(шашки.лучший === 2, 'лучший у шашек — 2, а не дураковы 7');
    проверить(таблицей(дурак) === '7 сложный | 1 обычный', 'дурак видит старый ключ и свою победу, шашек не видит');
    проверить(память.ящик['records_shashki'] !== undefined, 'шашки легли в records_shashki');
    проверить(память.ящик['records_durak'] !== undefined, 'дурак лёг в records_durak');
    проверить(Object.keys(память.ящик).length === 3, 'в памяти ровно три ключа: старый, дурак, шашки');
  }

  console.log('=== 3. Серии двух игр не мешают друг другу через заметку о серии ===');
  {
    const х = завести(НОВЫЙ, сделатьПамять(), null);
    await х.saveScore(1, 'обычный');
    await х.saveScore(1, 'обычный', 'шашки');
    await х.saveScore(2, 'обычный');
    await х.saveScore(2, 'обычный', 'шашки');
    await х.saveScore(3, 'обычный', 'шашки');
    const д = await х.loadScore('дурак');
    const ш = await х.loadScore('шашки');
    console.log('  дурак: ' + таблицей(д) + '  |  шашки: ' + таблицей(ш));
    проверить(таблицей(д) === '2 обычный', 'дурак — одна строка «2»');
    проверить(таблицей(ш) === '3 обычный', 'шашки — одна строка «3»');
  }

  console.log('=== 4. Мусор вместо игры — это дурак (как и раньше без довода) ===');
  {
    const х = завести(НОВЫЙ, сделатьПамять(), null);
    await х.saveScore(1, 'обычный', 42);
    await х.saveScore(2, 'обычный', '');
    await х.saveScore(3, 'обычный', {});
    await х.saveScore(4, 'обычный', '   ');
    const д = await х.loadScore(null);
    console.log('  дурак: ' + таблицей(д) + ', ключи [' + ключиПамяти(х.память) + ']');
    проверить(таблицей(д) === '4 обычный', 'все четыре вызова легли в одну дуракову серию');
    проверить(ключиПамяти(х.память) === 'records_durak', 'ключ один — records_durak');
  }

  console.log('=== 5. Незнакомая игра: ключ из числа, латинский, одно предупреждение ===');
  {
    const предупреждения = [];
    const облако = сделатьОблако();
    const х = завести(НОВЫЙ, сделатьПамять(), облако, предупреждения);
    await х.saveScore(1, 'обычный', 'проверочная-игра');
    await х.saveScore(2, 'обычный', 'проверочная-игра');
    const н = await х.loadScore('проверочная-игра');
    const д = await х.loadScore();
    const ключи = Object.keys(х.память.ящик);
    console.log('  ключи памяти: [' + ключи.join(', ') + '], в облаке: [' + Object.keys(облако.ящик).join(', ') + ']');
    console.log('  предупреждений: ' + предупреждения.length + (предупреждения[0] ? ' — «' + предупреждения[0].slice(0, 70) + '…»' : ''));
    проверить(ключи.length === 1 && /^records_[a-z0-9]+$/.test(ключи[0]) && ключи[0] !== 'records_durak', 'ключ незнакомой игры — латинский, из числа, не дураков');
    проверить(облако.отказы.length === 0, 'облако ни разу не отказало по имени ключа');
    проверить(Object.keys(облако.ящик).length === 1, 'запись незнакомой игры дошла до облака');
    проверить(таблицей(н) === '2 обычный', 'незнакомая игра читается своей таблицей');
    проверить(таблицей(д) === '', 'у дурака при этом пусто');
    проверить(предупреждения.length === 1, 'предупреждение в консоли ровно одно на много вызовов');
    проверить(/проверочная-игра/.test(предупреждения[0] || ''), 'в предупреждении названа сама игра');
  }

  console.log('=== 6. Поддельное облако: шашки и дурак под латинскими ключами, переезд с двух устройств ===');
  {
    const облако = сделатьОблако();
    const тел1 = завести(НОВЫЙ, сделатьПамять(), облако);
    await тел1.saveScore(1, 'сложный', 'шашки');
    await тел1.saveScore(2, 'сложный', 'шашки');
    await тел1.saveScore(1, 'лёгкий');
    const тел2 = завести(НОВЫЙ, сделатьПамять(), облако);
    const ш = await тел2.loadScore('шашки');
    const д = await тел2.loadScore();
    console.log('  в облаке: [' + Object.keys(облако.ящик).sort().join(', ') + '], отказов ' + облако.отказы.length);
    console.log('  второе устройство видит шашки: ' + таблицей(ш) + '; дурака: ' + таблицей(д));
    проверить(Object.keys(облако.ящик).sort().join(', ') === 'records_durak, records_shashki', 'в облаке два ключа, оба латиницей');
    проверить(облако.отказы.length === 0, 'облако не отказывало');
    проверить(таблицей(ш) === '2 сложный', 'шашки переехали на второе устройство');
    проверить(таблицей(д) === '1 лёгкий', 'дурак переехал на второе устройство');
  }

  console.log('\nпроверок сделано: ' + проверок);
  if (беды.length) { console.log('=== ИТОГ: ЕСТЬ БЕДЫ (' + беды.length + ') ==='); беды.forEach(б => console.log('  - ' + б)); process.exit(1); }
  console.log('=== ИТОГ: довод «игра» работает, у дурака ничего не изменилось ===');
})();
