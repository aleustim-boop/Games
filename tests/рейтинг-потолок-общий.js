let всегоПроверок = 0;
let провалов = 0;
function проверить(что, условие, подробности) {
  всегоПроверок++;
  if (условие) { console.log('  ок     ' + что); return; }
  провалов++;
  console.log('  ПРОВАЛ ' + что + (подробности ? ': ' + подробности : ''));
}

/** Заменить ровно одно вхождение, иначе приём порчи устарел — сказать вслух. */
function заменитьРовноОдин(файл, старое, новое) {
  const части = fs.readFileSync(файл, 'utf8').split(старое);
  if (части.length !== 2) {
    throw new Error('приём порчи устарел: «' + старое + '» встречается в ' + файл + ' ' +
      (части.length - 1) + ' раз(а) вместо одного — поправьте проверку тем же коммитом');
  }
  fs.writeFileSync(файл, части.join(новое), 'utf8');
}

/** Откуда брать код: из проекта или из испорченной копии. */
function кодИзКопииИлиПроекта() {
  if (!ЛОМАТЬ) return ПРОЕКТ;
  const аргумент = process.argv[гдеЛомать + 1];

  /* Режим ломания: --сломать портит оба файла (по умолчанию),
     --сломать рейтинг портит только рейтинг,
     --сломать билеты портит только билеты. */
  let режим = 'оба';
  if (аргумент && аргумент.indexOf('--') !== 0) {
    if (аргумент === 'рейтинг' || аргумент === 'билеты') {
      режим = аргумент;
    } else {
      // Неизвестное слово — запрещаем
      console.error('ОШИБКА: после --сломать допускаются только режимы: рейтинг, билеты или ничего (оба)');
      process.exit(2);
    }
  }
  // Копия ВСЕГДА во временной папке, не в проекте
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'рейтинг-потолок-общий-сломать-'));
  fs.mkdirSync(папка, { recursive: true });
  // Боевые данные в копию не везём — они не нужны и не наши.
  fs.cpSync(path.join(ПРОЕКТ, 'server'), path.join(папка, 'server'), {
    recursive: true,
    filter: function (откуда) {
      const имя = path.basename(откуда);
      return имя !== 'данные' && имя !== 'node_modules';
    }
  });
  require('./пути-проекта.js').создатьПапкиКода(папка);
  fs.copyFileSync(path.join(ПРОЕКТ, 'общее', 'js', 'игры-реестр.js'), path.join(папка, 'общее', 'js', 'игры-реестр.js'));

  const портитьРейтинг = режим === 'оба' || режим === 'рейтинг';
  const портитьБилеты = режим === 'оба' || режим === 'билеты';

  // Порча рейтинга: потолок снова считается по записи одной игры.
  if (портитьРейтинг) {
    заменитьРовноОдин(path.join(папка, 'server', 'рейтинг.js'),
      'ПОТОЛОК_ОТ_БОТОВ_В_СУТКИ - взятоОтБотовСегодня(запись.номер, сегодня)',
      'ПОТОЛОК_ОТ_БОТОВ_В_СУТКИ - запись.очкиОтБотовЗаДень /* ИСПОРЧЕНО --сломать рейтинг */');
  }
  // Порча билетов: они не спрашивают общий потолок.
  if (портитьБилеты) {
    заменитьРовноОдин(path.join(папка, 'server', 'билеты.js'),
      'рейтинг.осталосьОтБотовСегодня(номер)',
      'рейтинг.ЦЕНА && 12 /* ИСПОРЧЕНО --сломать билеты */');
  }
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: ' + (портитьРейтинг ? 'рейтинг ' : '') +
    (портитьБилеты ? 'билеты ' : '') + 'из копии ' + папка + ' — прогон обязан провалиться ***\n');
  return папка;
}

