/** Живой игрок и бот за столом — как в tests/очки-рейтинга.js. */
function человек(номер, исход) {
  return { номер: номер, имя: 'И' + номер, этоБот: false,
    победил: исход === 'победа', ничья: исход === 'ничья' };
}
function бот(уровень, исход) {
  return { этоБот: true, уровень: уровень, победил: исход === 'победа', ничья: исход === 'ничья' };
}

/** Очки игрока в одной игре. */
function очки(номер, игра) {
  const срез = рейтинг.срезДляИгрока(игра, номер);
  return срез.я ? срез.я.очки : 0;
}

/** «2026-09-30» по местному времени — тот же вид, что у рейтинга. */
function ключДня(время) {
  const д = new Date(время);
  return д.getFullYear() + '-' + String(д.getMonth() + 1).padStart(2, '0') + '-' +
    String(д.getDate()).padStart(2, '0');
}

