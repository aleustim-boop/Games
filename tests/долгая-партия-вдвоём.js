'use strict';

/* =====================================================================
   Долгая партия вдвоём: доживает ли стол до конца, если игроки думают.

   Зачем. В браузере партия двух живых игроков однажды оборвалась
   на середине: сервер ответил «такой комнаты нет», обоих выбросило
   на экран «Игра с другом» со словами «Игра закрылась: сервер её
   больше не помнит». Партия шла минуты три-четыре. Этот скрипт
   повторяет тот случай нарочно: два игрока ходят медленно (по паре
   секунд на ход, как живые люди), и мы смотрим, доживёт ли комната
   до конца партии.

   Как запускать:

       node tests/долгая-партия-вдвоём.js
       node tests/долгая-партия-вдвоём.js 8790 3000

   Второе число — сколько секунд «думает» каждый игрок над ходом
   (в миллисекундах). Чем больше, тем дольше партия.
   ===================================================================== */

const http = require('http');

const ПОРТ = Number(process.argv[2]) || 8790;
const РАЗДУМЬЕ = Number(process.argv[3]) || 3000;
const ХОЗЯИН = '127.0.0.1';

function спросить(путь, тело) {
  return new Promise((готово, беда) => {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, (ответ) => {
      let текст = '';
      ответ.setEncoding('utf8');
      ответ.on('data', (к) => { текст += к; });
      ответ.on('end', () => {
        let р = null;
        try { р = JSON.parse(текст); } catch (сбой) { р = { сырое: текст }; }
        готово({ код: ответ.statusCode, тело: р });
      });
    });
    запрос.setTimeout(40000, () => запрос.destroy(new Error('сервер молчит')));
    запрос.on('error', беда);
    запрос.end(данные);
  });
}

const пауза = (мс) => new Promise((r) => setTimeout(r, мс));

function бьёт(чем, что, козырь) {
  if (чем.масть === что.масть) return чем.вес > что.вес;
  return чем.масть === козырь && что.масть !== козырь;
}

function решить(вид) {
  const рука = вид.мояРука || [];
  const стол = вид.стол || [];
  const козырь = вид.козырь;
  const яОтбиваюсь = вид.яОтбиваюсь !== undefined ? вид.яОтбиваюсь : (!вид.яАтакую && стол.length > 0);

  if (яОтбиваюсь && !вид.берут) {
    let номер = -1;
    for (let i = 0; i < стол.length; i++) { if (!стол[i].защита) { номер = i; break; } }
    if (номер < 0) return null;
    const атака = стол[номер].атака;
    const годные = рука.map((к, i) => ({ к, i }))
      .filter((п) => атака && бьёт(п.к, атака, козырь))
      .sort((а, б) => (а.к.масть === козырь ? 1 : 0) - (б.к.масть === козырь ? 1 : 0) || а.к.вес - б.к.вес);
    if (годные.length) return { действие: 'отбить', пара: номер, карта: годные[0].i };
    return { действие: 'беру' };
  }

  if (вид.яХожу) {
    // Карт не осталось, а стол ещё не закрыт — говорим «бито», иначе все ждут нас
    if (!рука.length) return стол.length ? { действие: 'бито' } : null;
    if (!стол.length) {
      const порядок = рука.map((к, i) => ({ к, i }))
        .sort((а, б) => (а.к.масть === козырь ? 1 : 0) - (б.к.масть === козырь ? 1 : 0) || а.к.вес - б.к.вес);
      return { действие: 'ходить', карта: порядок[0].i };
    }
    const веса = new Set();
    стол.forEach((п) => { if (п.атака) веса.add(п.атака.вес); if (п.защита) веса.add(п.защита.вес); });
    const годная = рука.findIndex((к) => веса.has(к.вес) && к.масть !== козырь);
    if (годная >= 0) return { действие: 'ходить', карта: годная };
    return { действие: 'бито' };
  }
  return null;
}

async function главная() {
  const начало = Date.now();
  const прошло = () => Math.round((Date.now() - начало) / 1000) + ' сек';

  const создано = await спросить('/создать', { имя: 'Первый' });
  const код = создано.тело.код;
  const пропуск1 = создано.тело.пропуск;
  console.log('Комната ' + код + ' создана (' + прошло() + ')');

  const вход = await спросить('/войти', { код, имя: 'Второй' });
  if (вход.код !== 200) { console.log('Второй не вошёл: ' + вход.код); return; }
  const пропуск2 = вход.тело.пропуск;
  console.log('Второй вошёл, карты розданы (' + прошло() + ')');

  const игроки = [{ имя: 'Первый', пропуск: пропуск1 }, { имя: 'Второй', пропуск: пропуск2 }];
  let ходов = 0;
  let кругБезХодов = 0;

  for (let круг = 0; круг < 1000; круг++) {
    const ходовБыло = ходов;
    for (const игрок of игроки) {
      const с = await спросить('/состояние', { код, пропуск: игрок.пропуск });
      if (с.код !== 200) {
        console.log('ОБОРВАЛОСЬ на ' + прошло() + ': сервер ответил ' + с.код +
          ' игроку «' + игрок.имя + '». Сделано ходов: ' + ходов);
        console.log('Ответ сервера: ' + JSON.stringify(с.тело).slice(0, 200));
        return;
      }
      const вид = с.тело.состояние || с.тело;
      if (вид.завершена) {
        console.log('Партия доиграна за ' + прошло() + ', ходов: ' + ходов + ', итог для «' + игрок.имя + '»: ' + вид.итог);
        return;
      }
      const намерение = решить(вид);
      if (!намерение) continue;
      const о = await спросить('/ход', Object.assign({ код, пропуск: игрок.пропуск }, намерение));
      if (о.код !== 200) {
        console.log('ОБОРВАЛОСЬ на ходе, ' + прошло() + ': сервер ответил ' + о.код);
        return;
      }
      if (о.тело && о.тело.принято === false) {
        console.log('отказ игроку «' + игрок.имя + '»: ' + о.тело.причина);
        // отказ по правилам подкидывания — просто закрываем подход
        if (/подкид|меньше карт/i.test(о.тело.причина || '')) {
          await спросить('/ход', { код, пропуск: игрок.пропуск, действие: 'бито' });
        }
      } else {
        ходов++;
      }
      await пауза(РАЗДУМЬЕ);
    }
    /* Если целый круг никто не сделал ни одного хода — стол замер.
       Печатаем, что видит каждый: так понятно, кого игра ждёт. */
    if (ходов === ходовБыло) {
      кругБезХодов++;
      if (кругБезХодов >= 5) {
        console.log('СТОЛ ЗАМЕР на ' + прошло() + ', ходов сделано: ' + ходов);
        for (const игрок of игроки) {
          const с = await спросить('/состояние', { код, пропуск: игрок.пропуск });
          const в = (с.тело && (с.тело.состояние || с.тело)) || {};
          console.log('  «' + игрок.имя + '»: фаза ' + в.фаза + ', я хожу ' + в.яХожу +
            ', я атакую ' + в.яАтакую + ', берут ' + в.берут +
            ', карт в руке ' + (в.мояРука || []).length + ', на столе пар ' + (в.стол || []).length +
            ', в колоде ' + в.вКолоде + ', у соперника ' + в.картУСоперника);
        }
        return;
      }
      await пауза(1000);
    } else {
      кругБезХодов = 0;
    }
  }
  console.log('Партия так и не кончилась за ' + прошло());
}

главная().catch((сбой) => { console.error('Сорвалось: ' + сбой.message); process.exitCode = 1; });
