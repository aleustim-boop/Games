/** Рассадка одной строкой: «1=Хозяин, 2=Гость, 3=Бот 3». По ней видно,
    поменялось ли что-нибудь после злого запроса. */
function рассадкаСтрокой(состояние) {
  const места = (состояние && состояние.застолом) || [];
  return места.map(function (м) { return м.номер + '=' + м.имя; }).join(', ');
}

function имяМеста(состояние, номер) {
  const места = (состояние && состояние.застолом) || [];
  const место = места.filter(function (м) { return м.номер === номер; })[0];
  return место ? место.имя : '(пусто)';
}

function кто(состояние, признак) {
  const места = (состояние && состояние.застолом) || [];
  const место = места.filter(function (м) { return м[признак] === true; })[0];
  return место ? место.номер : null;
}

/** Свежий взгляд на стол глазами игрока. */
async function состояние(игрок) {
  const о = await спросить('/состояние', { код: игрок.код, пропуск: игрок.пропуск });
  игрок.вид = (о.тело && о.тело.состояние) || {};
  return игрок.вид;
}

/** Любое действие от имени игрока. */
async function действие(игрок, что) {
  const тело = Object.assign({ код: игрок.код, пропуск: игрок.пропуск }, что);
  const о = await спросить('/ход', тело);
  if (о.тело && о.тело.состояние) игрок.вид = о.тело.состояние;
  return о;
}

/* =====================================================================
   ЧАСТЬ 0. Умеет ли сыщик вообще ловить

   Проверка, которая ничего не ловит, выглядит точно так же, как игра
   без единой утечки. Поэтому сначала показываем сыщику заведомо
   испорченный ответ и убеждаемся, что он поднял тревогу.
   ===================================================================== */

function самопроверкаСыщика() {
  console.log('0. Сыщик умеет находить утечку');

  const партия = партии.начатьПартию(null, { игроки: [партии.ПЕРВЫЙ, партии.ВТОРОЙ] });
  const чужая = партия.руки[партии.ВТОРОЙ][0];

  const испорченный = { мояРука: [], тайник: { где: 'глубоко', карта: чужая } };
  const беды = найтиЧужие(испорченный, запрещённыеКарты(партия, партии.ПЕРВЫЙ));
  проверить(беды.length > 0, 'сыщик обязан найти чужую карту, закопанную в ответ, — а не нашёл');

  const честный = { мояРука: партия.руки[партии.ПЕРВЫЙ].slice() };
  проверить(найтиЧужие(честный, запрещённыеКарты(партия, партии.ПЕРВЫЙ)).length === 0,
    'сыщик поднял тревогу на честном ответе — так он завалит всю проверку');

  /* И сыщик снаружи: карты у чужого места обязаны быть замечены.
     Подсовываем ему нарочно испорченный ответ. Чтобы этот нарочный
     провал не попал в общий счёт, на время пробы отводим жалобы
     в сторону — так же, как выше. */
  const испорченныйОтвет = { состояние: { застолом: [
    { номер: 1, имя: 'Я', этоЯ: true, карт: 6 },
    { номер: 2, имя: 'Сосед', этоЯ: false, карт: 6, рука: [чужая] }
  ] } };
  нарочнаяПроба = [];
  осмотретьОтвет('(нарочно испорченный ответ)', JSON.stringify(испорченныйОтвет), испорченныйОтвет);
  const заметил = нарочнаяПроба.length > 0;
  нарочнаяПроба = null;
  проверить(заметил, 'сыщик снаружи обязан заметить карты у чужого места — а не заметил');

  /* И наоборот: на честном ответе, где у соседа только число карт,
     сыщик снаружи обязан молчать. */
  const честныйОтвет = { состояние: { застолом: [
    { номер: 1, имя: 'Я', этоЯ: true, карт: 6 },
    { номер: 2, имя: 'Сосед', этоЯ: false, карт: 6 }
  ] } };
  нарочнаяПроба = [];
  осмотретьОтвет('(честный ответ)', JSON.stringify(честныйОтвет), честныйОтвет);
  const промолчал = нарочнаяПроба.length === 0;
  нарочнаяПроба = null;
  проверить(промолчал, 'сыщик снаружи поднял тревогу на честном ответе — так он завалит всю проверку');
}

