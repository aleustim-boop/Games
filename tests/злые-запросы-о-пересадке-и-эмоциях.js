/* Что сервер ОБЕЩАЛ игрокам. Это не пересказ правила, а договор: слова
   «не чаще одного знака в две секунды и не больше пяти за пятнадцать»
   сказаны штабу и записаны в задачу. Проверка ниже сверяет с ними только
   одно — не стала ли защита СЛАБЕЕ обещанной. Строже обещанного — не беда,
   об этом просто печатается строчка. */
const ОБЕЩАНО = { пауза: 2000, сколько: 5, окно: 15000 };

async function частьЧастыхНажатий(правило) {
  console.log('7. Защита от частых нажатий');
  if (!правило) {
    console.log('   ПРОВЕРИТЬ НЕ УДАЛОСЬ: числа «не чаще, чем...» не вычитались из ' +
                'server/комнаты.js. Выдумывать их проверка не станет.');
    проверить(false, 'числа защиты от частых нажатий не удалось прочитать из server/комнаты.js');
    return;
  }
  console.log('   правило из кода: не чаще одного знака в ' + (правило.пауза / 1000) +
              ' с и не больше ' + правило.сколько + ' за ' + (правило.окно / 1000) + ' с');

  // Защита не должна быть слабее того, что обещано игрокам.
  проверить(правило.пауза >= ОБЕЩАНО.пауза,
    'обещана пауза ' + (ОБЕЩАНО.пауза / 1000) + ' с, а в коде стоит ' + (правило.пауза / 1000) + ' с');
  проверить(правило.сколько <= ОБЕЩАНО.сколько,
    'обещан потолок ' + ОБЕЩАНО.сколько + ' знаков, а в коде стоит ' + правило.сколько);
  проверить(правило.окно >= ОБЕЩАНО.окно,
    'обещано окно ' + (ОБЕЩАНО.окно / 1000) + ' с, а в коде стоит ' + (правило.окно / 1000) + ' с');
  if (правило.пауза > ОБЕЩАНО.пауза || правило.сколько < ОБЕЩАНО.сколько) {
    console.log('   (защита строже обещанного — это не беда, но штабу стоит знать)');
  }

  /* Для этой части нужен игрок с чистым счётом нажатий, поэтому берём
     отдельную комнату: у тех, кто за главным столом, окно уже начато. */
  const хозяин = { имя: 'Нетерпеливый', код: null, пропуск: null, вид: null };
  const создано = await спросить('/создать', { мест: 2, имя: 'Нетерпеливый' });
  хозяин.код = создано.тело.код;
  хозяин.пропуск = создано.тело.пропуск;
  хозяин.вид = создано.тело.состояние;

  // --- пауза после каждого знака
  const первый = await действие(хозяин, { действие: 'эмоция', номер: 0 });
  проверить(первый.тело && первый.тело.принято === true,
    'самый первый знак обязан пройти, а сервер ответил: ' +
    JSON.stringify(первый.тело && первый.тело.причина));

  const сразуЖе = await действие(хозяин, { действие: 'эмоция', номер: 1 });
  проверить(сразуЖе.тело && сразуЖе.тело.принято === false,
    'второй знак сразу же обязан быть отклонён — обещана пауза ' + (правило.пауза / 1000) + ' с');
  проверить(типПричины(сразуЖе), 'отказ за частые нажатия обязан объяснить причину словами');

  await спать(Math.max(100, правило.пауза - 700));
  const почтиДождались = await действие(хозяин, { действие: 'эмоция', номер: 1 });
  проверить(почтиДождались.тело && почтиДождались.тело.принято === false,
    'знак раньше обещанной паузы обязан быть отклонён');

  await спать(1000);
  const дождались = await действие(хозяин, { действие: 'эмоция', номер: 1 });
  проверить(дождались.тело && дождались.тело.принято === true,
    'после паузы знак обязан пройти, а сервер ответил: ' +
    JSON.stringify(дождались.тело && дождались.тело.причина));

  await спросить('/выйти', { код: хозяин.код, пропуск: хозяин.пропуск });

  // --- потолок за окно: молотим по кнопке без остановки
  const бешеный = { имя: 'Бешеный', код: null, пропуск: null, вид: null };
  const вторая = await спросить('/создать', { мест: 2, имя: 'Бешеный' });
  бешеный.код = вторая.тело.код;
  бешеный.пропуск = вторая.тело.пропуск;
  бешеный.вид = вторая.тело.состояние;

  /* Долбим ровно столько, сколько длится окно. Считать «сколько прошло»
     нажатие за нажатием с выдержкой паузы нельзя: поставь кто-нибудь
     потолок в пятьсот — проверка честно ушла бы считать на двадцать минут. */
  const началось = Date.now();
  let попыток = 0;
  let прошло = 0;
  while (Date.now() - началось < правило.окно) {
    const о = await действие(бешеный, { действие: 'эмоция', номер: попыток % 2 });
    попыток++;
    if (о.тело && о.тело.принято) прошло++;
    await спать(150);
  }
  console.log('   за ' + (правило.окно / 1000) + ' с непрерывного долбления: попыток ' +
              попыток + ', прошло ' + прошло);

  проверить(прошло <= правило.сколько,
    'за окно в ' + (правило.окно / 1000) + ' с обязано пройти не больше ' + правило.сколько +
    ' знаков, а прошло ' + прошло);
  проверить(прошло <= ОБЕЩАНО.сколько,
    'игрокам обещано не больше ' + ОБЕЩАНО.сколько + ' знаков за ' + (ОБЕЩАНО.окно / 1000) +
    ' с, а прошло ' + прошло);
  проверить(прошло >= 1, 'защита не должна глушить вообще всё: не прошло ни одного знака');
  проверить(попыток > прошло,
    'при непрерывном долблении часть нажатий обязана отсеиваться, а прошли все ' + попыток);

  await спросить('/выйти', { код: бешеный.код, пропуск: бешеный.пропуск });
}

/* =====================================================================
   ЧАСТИ 5 и 6. Пустые места и комната на двоих

   Два случая, до которых обычная игра пальцем не доходит, а злой запрос
   доходит легко:
     — за большим столом много пустых кресел: менять местами два пустых
       нельзя (менять нечего), а пересадить человека на пустое — можно;
     — старая комната на двоих: хозяин пересаживает себя на второе место
       ещё до того, как друг вошёл. Дальше друг обязан войти как ни
       в чём не бывало, и хозяин обязан остаться один.
   ===================================================================== */

async function частьПустыхМест() {
  console.log('5. Пустые места за большим столом');

  const хозяин = { имя: 'Один', код: null, пропуск: null, вид: null };
  const создано = await спросить('/создать', { мест: игра.МАКС_ИГРОКОВ, имя: 'Один' });
  хозяин.код = создано.тело.код;
  хозяин.пропуск = создано.тело.пропуск;
  хозяин.вид = создано.тело.состояние;

  const вид = await состояние(хозяин);
  const мест = Number(вид.мест) || 0;
  проверить(мест === игра.МАКС_ИГРОКОВ,
    'просили стол на ' + игра.МАКС_ИГРОКОВ + ' мест, а сервер дал ' + мест);

  const своё = кто(вид, 'этоЯ');
  const пустое = найтиСвободное(вид, мест);
  const второеПустое = найтиСвободное(вид, мест, пустое);
  проверить(пустое !== null && второеПустое !== null,
    'за столом на ' + мест + ' мест с одним игроком обязаны быть хотя бы два пустых кресла');

  if (пустое !== null && второеПустое !== null) {
    await злаяПересадка(хозяин, { откуда: пустое, куда: второеПустое },
      'двух пустых мест (' + пустое + ' и ' + второеПустое + ')');

    // А переехать на пустое кресло — можно, это обычное дело.
    const переезд = await действие(хозяин, { действие: 'пересадить', откуда: своё, куда: пустое });
    проверить(переезд.тело && переезд.тело.принято === true,
      'переезд на свободное кресло обязан пройти, а сервер ответил: ' +
      JSON.stringify(переезд.тело && переезд.тело.причина));
    const после = await состояние(хозяин);
    проверить(кто(после, 'этоЯ') === пустое,
      'после переезда игрок обязан сидеть на месте ' + пустое + ', а сидит на ' + кто(после, 'этоЯ'));
    проверить(кто(после, 'хозяин') === пустое, 'право хозяина обязано переехать вместе с ним');
    проверить((после.застолом || []).filter(function (м) { return м.хозяин; }).length === 1,
      'хозяин за столом обязан быть ровно один, а их ' +
      (после.застолом || []).filter(function (м) { return м.хозяин; }).length);
  }

  await спросить('/выйти', { код: хозяин.код, пропуск: хозяин.пропуск });
}

async function частьКомнатыНаДвоих() {
  console.log('6. Старая комната на двоих: пересадка до прихода друга');

  const хозяин = { имя: 'Первый', код: null, пропуск: null, вид: null };
  const друг = { имя: 'Второй', код: null, пропуск: null, вид: null };

  // Настроек не передаём вовсе — это та самая старая комната на двоих.
  const создано = await спросить('/создать', {});
  хозяин.код = создано.тело.код;
  хозяин.пропуск = создано.тело.пропуск;
  хозяин.вид = создано.тело.состояние;

  const попытка = await действие(хозяин, { действие: 'пересадить', откуда: 1, куда: 2 });
  const принято = Boolean(попытка.тело && попытка.тело.принято);
  console.log('   пересадка себя на пустое второе место: ' + (принято ? 'разрешена' : 'отклонена'));
  проверить(попытка.тело && typeof попытка.тело.принято === 'boolean',
    'на пересадку в комнате на двоих сервер обязан ответить «да» или «нет», а не промолчать');

  const вошёл = await спросить('/войти', { код: хозяин.код, метка: 'проверка-друг' });
  проверить(вошёл.код === 200 && вошёл.тело && вошёл.тело.пропуск,
    'друг обязан войти в комнату на двоих даже после пересадки хозяина, а получил код ' +
    вошёл.код + ': ' + JSON.stringify(вошёл.тело && вошёл.тело.причина));
  if (!(вошёл.тело && вошёл.тело.пропуск)) return;

  друг.код = хозяин.код;
  друг.пропуск = вошёл.тело.пропуск;

  const уХозяина = await состояние(хозяин);
  const уДруга = await состояние(друг);
  проверить(уХозяина.этап === 'игра',
    'в комнате на двоих карты обязаны раздаться сразу, как вошёл друг, а этап «' + уХозяина.этап + '»');
  проверить((уХозяина.мояРука || []).length === игра.КАРТ_В_РУКЕ &&
            (уДруга.мояРука || []).length === игра.КАРТ_В_РУКЕ,
    'обоим обязано прийти по ' + игра.КАРТ_В_РУКЕ + ' карт, а пришло ' +
    (уХозяина.мояРука || []).length + ' и ' + (уДруга.мояРука || []).length);
  проверить(уХозяина.яХожу !== уДруга.яХожу,
    'ходить обязан ровно один из двоих, а сервер говорит: хозяин ' + уХозяина.яХожу +
    ', друг ' + уДруга.яХожу);

  const своиКарты = new Set((уХозяина.мояРука || []).map(ключКарты));
  const чужиеУДруга = (уДруга.мояРука || []).filter(function (к) { return своиКарты.has(ключКарты(к)); });
  проверить(чужиеУДруга.length === 0,
    'одна и та же карта не может быть на руках у обоих, а таких ' + чужиеУДруга.length);

  await спросить('/выйти', { код: хозяин.код, пропуск: хозяин.пропуск });
  await спросить('/выйти', { код: друг.код, пропуск: друг.пропуск });
}

/* =====================================================================
   ЧАСТЬ 4. Пересадка после раздачи и во время партии.
   Заодно — утечка чужих карт при живой партии.
   ===================================================================== */

async function частьПослеРаздачи(хозяин, гость, знаков) {
  console.log('4. После раздачи пересаживать нельзя, а карты соседей не видны');

  const начали = await действие(хозяин, { действие: 'начать' });
  проверить(начали.тело && начали.тело.принято === true,
    'хозяин обязан суметь начать партию, а сервер ответил: ' +
    JSON.stringify(начали.тело && начали.тело.причина));

  const вид = await состояние(хозяин);
  проверить(вид.этап === 'игра', 'после «Начать» этап обязан стать «игра», а он «' + вид.этап + '»');
  проверить(Array.isArray(вид.мояРука) && вид.мояРука.length === игра.КАРТ_В_РУКЕ,
    'на руку обязано прийти ' + игра.КАРТ_В_РУКЕ + ' карт, а пришло ' +
    (вид.мояРука || []).length);

  const мест = Number(вид.мест) || (вид.застолом || []).length;
  const рассадкаБыла = рассадкаСтрокой(вид);

  for (let откуда = 1; откуда <= мест; откуда++) {
    for (let куда = 1; куда <= мест; куда++) {
      if (откуда === куда) continue;
      const о = await действие(хозяин, { действие: 'пересадить', откуда: откуда, куда: куда });
      проверить(о.тело && о.тело.принято === false,
        'пересадка ' + откуда + '→' + куда + ' после раздачи обязана быть отклонена');
      проверить(типПричины(о), 'отказ на позднюю пересадку обязан объяснить причину словами');
    }
  }
  проверить(рассадкаСтрокой(await состояние(хозяин)) === рассадкаБыла,
    'после всех отклонённых поздних пересадок рассадка обязана остаться прежней');

  // И от не хозяина — тоже нельзя.
  const отГостя = await действие(гость, { действие: 'пересадить', откуда: 1, куда: 2 });
  проверить(отГостя.тело && отГостя.тело.принято === false,
    'пересадка от гостя после раздачи обязана быть отклонена');

  /* Играем настоящую партию: за каждый ответ сервера отвечает сыщик,
     а нам нужно просто, чтобы ответов было много и в них были карты. */
  const сыграно = await доигратьПартию([хозяин, гость]);
  console.log('   партия доиграна за ' + сыграно.шагов + ' шагов, чужих карт в ответах: ' +
              (сыграно.утечек ? сыграно.утечек : 'ни одной'));
  проверить(сыграно.доиграли, 'партия обязана доиграться до конца, а она встала на ' +
                              сыграно.шагов + ' шаге');
}

/** Один законный ход за игрока — какой угодно. */
async function походитьЗаСебя(игрок) {
  const вид = игрок.вид || {};
  const рука = вид.мояРука || [];
  if (вид.яОтбиваюсь || вид.фаза === 'защита') {
    for (let к = 0; к < рука.length; к++) {
      for (let пара = 0; пара < (вид.стол || []).length; пара++) {
        const о = await действие(игрок, { действие: 'отбить', карта: к, пара: пара });
        if (о.тело && о.тело.принято) return true;
      }
    }
  }
  for (let к = 0; к < рука.length; к++) {
    const о = await действие(игрок, { действие: 'ходить', карта: к });
    if (о.тело && о.тело.принято) return true;
  }
  for (const слово of ['бито', 'беру', 'пас']) {
    const о = await действие(игрок, { действие: слово });
    if (о.тело && о.тело.принято) return true;
  }
  return false;
}

async function доигратьПартию(игроки) {
  const ПРЕДЕЛ = 900;
  let шагов = 0;
  for (; шагов < ПРЕДЕЛ; шагов++) {
    let ходил = false;
    for (const игрок of игроки) {
      await состояние(игрок);
      if (игрок.вид.завершена) return { доиграли: true, шагов: шагов, утечек: 0 };
      if (await походитьЗаСебя(игрок)) ходил = true;
    }
    if (!ходил) await спать(партии.ПАУЗА_БОТА + 60);   // ждём ботов
  }
  return { доиграли: false, шагов: шагов, утечек: 0 };
}

/* =====================================================================
   Сборка стола и запуск
   ===================================================================== */

async function собратьСтол() {
  const хозяин = { имя: 'Хозяин', код: null, пропуск: null, вид: null };
  const гость = { имя: 'Гость', код: null, пропуск: null, вид: null };

  const создано = await спросить('/создать', { мест: 4, имя: 'Хозяин' });
  if (!создано.тело || !создано.тело.код) {
    throw new Error('комнату создать не вышло: ' + JSON.stringify(создано.тело));
  }
  хозяин.код = создано.тело.код;
  хозяин.пропуск = создано.тело.пропуск;
  хозяин.вид = создано.тело.состояние;

  const вошёл = await спросить('/войти', { код: хозяин.код, имя: 'Гость', метка: 'проверка-гость' });
  if (!вошёл.тело || !вошёл.тело.пропуск) {
    throw new Error('гость войти не смог: ' + JSON.stringify(вошёл.тело));
  }
  гость.код = хозяин.код;
  гость.пропуск = вошёл.тело.пропуск;
  гость.вид = вошёл.тело.состояние;

  // Добираем стол ботами, чтобы можно было начать партию.
  for (let н = 0; н < 2; н++) {
    await действие(хозяин, { действие: 'бот' });
  }
  return { хозяин: хозяин, гость: гость };
}

