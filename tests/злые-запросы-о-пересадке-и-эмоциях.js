/* Идёт нарочная проба «а ловит ли сыщик»? Тогда его находки — не беда
   игры, а признак того, что сыщик работает. Они складываются сюда
   и в общий счёт не идут. */
let нарочнаяПроба = null;

/* Сколько провалов печатаем подробно. Дальше только считаем: одна
   протёкшая карта видна в сотнях ответов, и без потолка проверка
   утонула бы в собственном выводе (проверено — прогон вставал). */
const ПЕЧАТАЕМ_ПРОВАЛОВ = 40;
let провалыСверхПотолка = 0;

function проверить(условие, что) {
  if (нарочнаяПроба) {
    if (!условие) нарочнаяПроба.push(что);
    return;
  }
  проверок++;
  if (!условие) {
    if (провалы.length < ПЕЧАТАЕМ_ПРОВАЛОВ) {
      провалы.push(что);
      console.log('  ПРОВАЛ: ' + что);
    } else {
      провалыСверхПотолка++;
    }
  }
}

/** Всего провалов — и напечатанных, и тех, что не поместились. */
function всегоПровалов() {
  return провалы.length + провалыСверхПотолка;
}

