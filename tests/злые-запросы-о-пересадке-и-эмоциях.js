function спросить(путь, тело) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело === undefined ? {} : тело), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН_АДРЕС, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (ч) { текст += ч; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (е) { разобрано = { сырое: текст }; }
        осмотретьОтвет(путь, текст, разобрано);
        готово({ код: ответ.statusCode, тело: разобрано, текст: текст });
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

/* ---------------------------------------------------------------------
   Сыщик №1: смотрит КАЖДЫЙ ответ сервера снаружи, как посторонний.

   Ему не видно тайного состояния партии, зато видно всё, что уехало
   в браузер. Он ищет две вещи: внутренние названия мест ('человек',
   'бот-3') и карты у чужих мест. Про соседей в ответе должно быть
   только ЧИСЛО карт — за этим и следим.
   --------------------------------------------------------------------- */

/** Похоже ли это на карту: у карты в игре всегда есть масть и имя. */
function этоКарта(что) {
  return что && typeof что === 'object' &&
         typeof что.масть === 'string' && typeof что.имя === 'string';
}

/** Собрать все карты из куска ответа, на любой глубине. */
function картыВнутри(что, найденные) {
  const список = найденные || [];
  if (!что || typeof что !== 'object') return список;
  if (Array.isArray(что)) {
    for (const кусок of что) картыВнутри(кусок, список);
    return список;
  }
  if (этоКарта(что)) список.push(что);
  for (const ключ of Object.keys(что)) картыВнутри(что[ключ], список);
  return список;
}

function осмотретьОтвет(путь, текст, разобрано) {
  ответовОсмотрено++;

  if (текст.indexOf('"колода"') !== -1) {
    проверить(false, 'в ответе ' + путь + ' оказалась колода целиком');
  }
  if (текст.indexOf('"руки"') !== -1) {
    проверить(false, 'в ответе ' + путь + ' оказались руки всех игроков');
  }
  if (текст.indexOf('"человек"') !== -1 || текст.indexOf('"бот-') !== -1) {
    проверить(false, 'в ответе ' + путь + ' видны внутренние названия мест');
  }

  const состояние = разобрано && разобрано.состояние;
  if (!состояние || !Array.isArray(состояние.застолом)) return;

  for (const место of состояние.застолом) {
    if (typeof место.карт !== 'number' || !Number.isFinite(место.карт)) {
      проверить(false, 'у места ' + место.номер + ' число карт пришло не числом: ' +
                       JSON.stringify(место.карт));
    }
    if (место.этоЯ === true) continue;
    const карты = картыВнутри(место);
    if (карты.length > 0) {
      проверить(false, 'в ответе ' + путь + ' у чужого места ' + место.номер +
                       ' пришли сами карты, а не их число: ' + JSON.stringify(карты[0]));
    }
  }
}

/* ---------------------------------------------------------------------
   Сыщик №2: стоит внутри, у единственной двери наружу.

   Он видит и тайное состояние партии, и то, что уходит игроку, поэтому
   умеет сказать точно: «вот эта карта лежит в руке у соседа, а её видно
   в ответе». Сыщик снаружи такого сказать не может — он не знает,
   чья карта чужая.

   Устроен так же, как сыщик в штатной проверке server/проверка-двух-
   игроков.js, но считает чужими руки ВСЕХ соседей, а не одного:
   за столом компанией их бывает до пяти.
   --------------------------------------------------------------------- */

function ключКарты(карта) { return карта.масть + карта.имя; }

function запрещённыеКарты(партия, ктоЯ) {
  const запрет = new Map();
  const колодаЦела = партия.колода.length > 0;
  const открытая = колодаЦела && партия.козырнаяКарта ? ключКарты(партия.козырнаяКарта) : null;

  const добавить = function (карта, откуда) {
    const ключ = ключКарты(карта);
    if (ключ === открытая) return;    // козырь под колодой лежит лицом вверх
    запрет.set(ключ, откуда);
  };

  for (const имя of Object.keys(партия.руки || {})) {
    if (имя === ктоЯ) continue;
    for (const карта of партия.руки[имя]) добавить(карта, 'чужая рука');
  }
  for (const карта of партия.колода) добавить(карта, 'колода');
  for (const карта of партия.отбой) добавить(карта, 'отбой');
  return запрет;
}

function найтиЧужие(вид, запрет) {
  const беды = [];
  for (const карта of картыВнутри(вид)) {
    const ключ = ключКарты(карта);
    if (запрет.has(ключ)) {
      беды.push('в ответе есть чужая карта ' + ключ + ' (' + запрет.get(ключ) + ')');
    }
  }
  const текст = JSON.stringify(вид);
  for (const [ключ, откуда] of запрет) {
    const кусок = '"масть":"' + ключ[0] + '","имя":"' + ключ.slice(1) + '"';
    if (текст.indexOf(кусок) !== -1) {
      беды.push('в тексте ответа видна чужая карта ' + ключ + ' (' + откуда + ')');
    }
  }
  return беды;
}

const настоящийВид = партии.видДляИгрока;
let видовОсмотрено = 0;

function поставитьСыщика() {
  партии.видДляИгрока = function (партия, ктоЯ, добавка) {
    const вид = настоящийВид(партия, ктоЯ, добавка);
    if (!партия) return вид;
    видовОсмотрено++;
    for (const беда of найтиЧужие(вид, запрещённыеКарты(партия, ктоЯ))) проверить(false, беда);
    const текст = JSON.stringify(вид);
    if (текст.indexOf('"колода"') !== -1) проверить(false, 'внутри вида оказалась колода');
    if (текст.indexOf('"руки"') !== -1) проверить(false, 'внутри вида оказались все руки');
    return вид;
  };
}

/* ---------------------------------------------------------------------
   Правило про частые нажатия — вычитываем из кода, а не помним

   Числа «две секунды» и «пять за пятнадцать» живут в server/комнаты.js
   и наружу не отдаются. Своей копии здесь заводить нельзя: поменяют
   там — проверка начнёт ругаться на верное поведение. Поэтому читаем
   их прямо из файла. Не вышло прочитать — говорим об этом вслух
   и пропускаем проверку, а не выдумываем числа.
   --------------------------------------------------------------------- */

function числоИзКода(текст, имя) {
  const найдено = new RegExp('const\\s+' + имя + '\\s*=\\s*([^;]+);').exec(текст);
  if (!найдено) return null;
  const выражение = найдено[1].trim();
  // Пускаем только простую арифметику: цифры, скобки и четыре действия.
  if (!/^[\d\s+\-*/().]+$/.test(выражение)) return null;
  try {
    const число = Function('"use strict"; return (' + выражение + ');')();
    return Number.isFinite(число) ? число : null;
  } catch (сбой) {
    return null;
  }
}

function правилоЧастоты() {
  const файл = path.join(КОРЕНЬ, 'server', 'комнаты.js');
  let текст = '';
  try { текст = fs.readFileSync(файл, 'utf8'); } catch (сбой) { return null; }
  const пауза = числоИзКода(текст, 'ПАУЗА_МЕЖДУ_ЗНАКАМИ');
  const сколько = числоИзКода(текст, 'ЗНАКОВ_ЗА_ОКНО');
  const окно = числоИзКода(текст, 'ОКНО_ЗНАКОВ');
  if (пауза === null || сколько === null || окно === null) return null;
  return { пауза: пауза, сколько: сколько, окно: окно };
}

