/** Один злой запрос на пересадку: обязан быть отклонён и ничего не менять. */
async function злаяПересадка(хозяин, что, зачем) {
  const до = рассадкаСтрокой(await состояние(хозяин));
  const о = await действие(хозяин, Object.assign({ действие: 'пересадить' }, что));
  const после = рассадкаСтрокой(await состояние(хозяин));

  проверить(о.тело && о.тело.принято === false, 'пересадка ' + зачем + ' обязана быть отклонена');
  проверить(типПричины(о), 'отказ на пересадку ' + зачем + ' обязан объяснить причину словами');
  проверить(до === после, 'после отклонённой пересадки (' + зачем + ') рассадка не должна меняться: ' +
                          'было «' + до + '», стало «' + после + '»');
}

/** Причина отказа — непустая строка для человека. */
function типПричины(о) {
  return Boolean(о.тело && typeof о.тело.причина === 'string' && о.тело.причина.trim().length > 0);
}

async function частьПересадки(хозяин, гость) {
  console.log('1. Пересадка: чего сервер не должен разрешать');

  const вид = await состояние(хозяин);
  const мест = Number(вид.мест) || (вид.застолом || []).length;
  console.log('   стол на ' + мест + ' мест, рассадка: ' + рассадкаСтрокой(вид));

  проверить(мест >= 2, 'за столом должно быть хотя бы два места, а сервер говорит: ' + вид.мест);
  проверить(вид.этап === 'ожидание', 'до раздачи этап обязан быть «ожидание», а он «' + вид.этап + '»');

  // --- просит не хозяин
  const доЧужого = рассадкаСтрокой(вид);
  const чужой = await действие(гость, { действие: 'пересадить', откуда: 1, куда: 2 });
  проверить(чужой.тело && чужой.тело.принято === false,
    'пересадку от НЕ хозяина сервер обязан отклонить');
  проверить(типПричины(чужой), 'отказ не хозяину обязан объяснить причину словами');
  проверить(рассадкаСтрокой(await состояние(хозяин)) === доЧужого,
    'после отказа не хозяину рассадка не должна меняться');

  // --- номера мест за пределами стола
  const запределы = [
    [0, 1, 'с места 0 (мест считают с единицы)'],
    [1, 0, 'на место 0'],
    [мест + 1, 1, 'с места ' + (мест + 1) + ' — за столом такого нет'],
    [1, мест + 1, 'на место ' + (мест + 1) + ' — за столом такого нет'],
    [игра.МАКС_ИГРОКОВ + 1, 1, 'с места больше самого большого стола'],
    [1, 999, 'на место 999'],
    [999999, 999998, 'между двумя выдуманными местами']
  ];
  for (const [откуда, куда, зачем] of запределы) {
    await злаяПересадка(хозяин, { откуда: откуда, куда: куда }, зачем);
  }

  // --- одинаковые места
  for (let м = 1; м <= мест; м++) {
    await злаяПересадка(хозяин, { откуда: м, куда: м }, 'места ' + м + ' самого с собой');
  }

  // --- дробные
  const дробные = [1.5, 2.5, 0.999, 1.0000001, мест + 0.5];
  for (const число of дробные) {
    await злаяПересадка(хозяин, { откуда: число, куда: 2 }, 'с дробного места ' + число);
    await злаяПересадка(хозяин, { откуда: 1, куда: число }, 'на дробное место ' + число);
  }

  // --- отрицательные
  for (const число of [-1, -2, -999]) {
    await злаяПересадка(хозяин, { откуда: число, куда: 2 }, 'с отрицательного места ' + число);
    await злаяПересадка(хозяин, { откуда: 1, куда: число }, 'на отрицательное место ' + число);
  }

  // --- строкой и прочей дрянью
  const дрянь = [
    ['1', 'строкой «1»'],
    ['2', 'строкой «2»'],
    ['1e0', 'строкой «1e0»'],
    [' 1 ', 'строкой с пробелами'],
    [null, 'null'],
    [undefined, 'без поля вовсе'],
    [true, 'значением «да»'],
    [false, 'значением «нет»'],
    [{}, 'объектом'],
    [{ номер: 1 }, 'объектом с номером внутри'],
    [[1], 'массивом'],
    [NaN, '«не число»'],
    [Infinity, '«бесконечностью»'],
    ['-1', 'строкой «-1»'],
    ['ой', 'словом «ой»'],
    ['1; DROP TABLE', 'строкой с посторонним хвостом']
  ];
  for (const [значение, зачем] of дрянь) {
    await злаяПересадка(хозяин, { откуда: значение, куда: 2 }, 'откуда ' + зачем);
    await злаяПересадка(хозяин, { откуда: 1, куда: значение }, 'куда ' + зачем);
  }

  // --- вовсе без полей
  await злаяПересадка(хозяин, {}, 'без указания мест');

  // --- пустые места: менять нечего
  const свободное = найтиСвободное(await состояние(хозяин), мест);
  const второеСвободное = найтиСвободное(await состояние(хозяин), мест, свободное);
  if (свободное && второеСвободное) {
    await злаяПересадка(хозяин, { откуда: свободное, куда: второеСвободное },
      'двух пустых мест (' + свободное + ' и ' + второеСвободное + ')');
  } else {
    console.log('   (двух свободных мест за столом нет — проверку «оба пустых» пропустил)');
  }
}

/** Номер места, на котором никто не сидит (кроме уже названного). */
function найтиСвободное(вид, мест, кроме) {
  const занято = {};
  for (const м of (вид.застолом || [])) занято[м.номер] = true;
  for (let н = 1; н <= мест; н++) {
    if (!занято[н] && н !== кроме) return н;
  }
  return null;
}

/* =====================================================================
   ЧАСТЬ 2. Пересадка: законная обязана проходить

   Без этой части вся первая часть ничего не стоит: наглухо сломанная
   пересадка, отвечающая «нельзя» вообще на всё, прошла бы её целиком.
   ===================================================================== */

async function частьЗаконнойПересадки(хозяин, гость) {
  console.log('2. Пересадка: законная проходит и делает своё дело');

  const до = await состояние(хозяин);
  const местоХозяина = кто(до, 'этоЯ');
  const местоГостя = (до.застолом || []).filter(function (м) {
    return !м.этоЯ && !м.этоБот;
  })[0];
  if (!местоГостя) {
    console.log('   (второго человека за столом нет — проверку пропустил)');
    return;
  }
  const номерГостя = местоГостя.номер;
  const имяХозяинаБыло = имяМеста(до, местоХозяина);
  const имяГостяБыло = имяМеста(до, номерГостя);
  проверить(кто(до, 'хозяин') === местоХозяина,
    'до пересадки хозяином должен числиться тот, кто создал комнату');

  const о = await действие(хозяин, { действие: 'пересадить', откуда: местоХозяина, куда: номерГостя });
  проверить(о.тело && о.тело.принято === true,
    'законную пересадку сервер обязан принять, а он ответил: ' +
    JSON.stringify(о.тело && о.тело.причина));

  const после = await состояние(хозяин);
  проверить(имяМеста(после, номерГостя) === имяХозяинаБыло,
    'после обмена хозяин обязан оказаться на месте ' + номерГостя + ': там «' +
    имяМеста(после, номерГостя) + '», а ждали «' + имяХозяинаБыло + '»');
  проверить(имяМеста(после, местоХозяина) === имяГостяБыло,
    'после обмена гость обязан оказаться на месте ' + местоХозяина + ': там «' +
    имяМеста(после, местоХозяина) + '», а ждали «' + имяГостяБыло + '»');

  // Хозяин — это место, и вместе с человеком переезжает и оно.
  проверить(кто(после, 'этоЯ') === номерГостя,
    'после пересадки хозяин должен видеть себя на новом месте');
  проверить(кто(после, 'хозяин') === номерГостя,
    'право хозяина обязано переехать вместе с ним, а оно осталось на месте ' +
    кто(после, 'хозяин'));

  // Гость смотрит на тот же стол и видит ту же рассадку.
  const глазамиГостя = await состояние(гость);
  проверить(рассадкаСтрокой(глазамиГостя) === рассадкаСтрокой(после),
    'гость обязан видеть ту же рассадку, что и хозяин: у него «' +
    рассадкаСтрокой(глазамиГостя) + '», у хозяина «' + рассадкаСтрокой(после) + '»');
  проверить(кто(глазамиГостя, 'этоЯ') === местоХозяина,
    'гость обязан увидеть себя на новом месте ' + местоХозяина +
    ', а видит на ' + кто(глазамиГостя, 'этоЯ'));
  проверить(кто(глазамиГостя, 'хозяин') === номерГостя,
    'гость обязан видеть хозяина на его новом месте');

  // Возвращаем всех обратно — дальше проще считать.
  const назад = await действие(хозяин, { действие: 'пересадить', откуда: номерГостя, куда: местоХозяина });
  проверить(назад.тело && назад.тело.принято === true, 'обратная пересадка тоже обязана пройти');
  const вернулись = await состояние(хозяин);
  проверить(рассадкаСтрокой(вернулись) === рассадкаСтрокой(до),
    'после пересадки туда и обратно рассадка обязана стать прежней: было «' +
    рассадкаСтрокой(до) + '», стало «' + рассадкаСтрокой(вернулись) + '»');
}

