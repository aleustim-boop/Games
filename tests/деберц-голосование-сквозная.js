/* ------------------------------------------------------------------
   Игра: ход любой доступной кнопкой или картой
   ------------------------------------------------------------------ */
async function нажатьКарту(с, карта) {
  await карта.evaluate(async к => { await Promise.allSettled(к.getAnimations().map(а => а.finished)); });
  const точка = await карта.evaluate(к => {
    const r = к.getBoundingClientRect();
    for (let y = r.top + 12; y < r.bottom - 8; y += 8) {
      for (let x = r.left + 6; x < r.right - 6; x += 5) {
        if (к.contains(document.elementFromPoint(x, y))) return { x, y };
      }
    }
    return null;
  });
  if (!точка) return false;
  await с.mouse.click(точка.x, точка.y);
  return true;
}

/** Сделать один ход, если есть чем. Возвращает описание хода или null. */
async function ходить(с) {
  try {
    const кнопка = с.locator('#панель-кнопок button:enabled:not(.кнопка--инфо):not(#кнопка-эмоции), #деберц-итог-действия button:enabled').first();
    if (await кнопка.isVisible({ timeout: 300 })) {
      const т = (await кнопка.textContent()).trim();
      if (!['Реванш', 'В лобби'].includes(т)) { await кнопка.click({ timeout: 1500 }); return 'кнопка «' + т + '»'; }
    }
    const карта = с.locator('#карты-человека button:enabled').first();
    if (await карта.isVisible({ timeout: 300 })) {
      if (await нажатьКарту(с, карта)) return 'карта';
    }
  } catch (_) { /* экран сменился под рукой — не ход */ }
  return null;
}

