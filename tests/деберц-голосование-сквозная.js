/* ------------------------------------------------------------------
   Служебное: свой сервер комнат и файловый сервер
   ------------------------------------------------------------------ */
function поднятьСерверКомнат(корень, порт, безДвери) {
  const доводы = [__filename, '--сервер', '--корень', корень, '--порт-комнат', String(порт)];
  if (безДвери) доводы.push('--без-двери');
  const п = spawn(process.execPath, доводы, { stdio: ['ignore', 'pipe', 'pipe', 'ipc'] });
  return new Promise((готово, беда) => {
    let вывод = '';
    const т = setTimeout(() => беда(new Error('сервер комнат не поднялся за 10 с. Вывод: ' + вывод)), 10000);
    п.stdout.on('data', d => { вывод += d.toString(); if (вывод.includes('работает')) { clearTimeout(т); готово(п); } });
    п.stderr.on('data', d => { вывод += d.toString(); console.log('  [сервер комнат, ошибка] ' + d.toString().trim()); });
    п.on('exit', код => { clearTimeout(т); беда(new Error('сервер комнат завершился (код ' + код + '). Вывод: ' + вывод)); });
  });
}

function поднятьФайловыйСервер(корень, порт) {
  const п = spawn(process.execPath, [path.join(ПРОЕКТ, 'tests', 'локальный-сервер.js'), String(порт)], {
    env: Object.assign({}, process.env, { КОРЕНЬ_СЕРВЕРА: корень }), stdio: 'pipe'
  });
  return new Promise((готово, беда) => {
    let вывод = '';
    const т = setTimeout(() => беда(new Error('файловый сервер не поднялся за 8 с')), 8000);
    п.stdout.on('data', d => { вывод += d.toString(); if (вывод.includes('запущен')) { clearTimeout(т); готово(п); } });
    п.on('error', e => { clearTимeout(т); беда(e); });
  });
}

function погасить(п) {
  if (!п || п.killed) return;
  try { п.removeAllListeners('exit'); } catch (_) { /* уже нечего */ }
  try { п.kill(); } catch (_) { /* уже погас */ }
}

