function сломать() {
  console.log('=== Ломающий режим: прогоны на испорченных копиях во временной папке ===');
  let покраснело = 0;
  ПОЛОМКИ.forEach((п, i) => {
    const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'деберц-голосование-лом' + (i + 1) + '-'));
    try {
      скопироватьПроект(папка);
      if (п.портить) п.портить(папка);
      console.log('\nПоломка ' + (i + 1) + ': ' + п.что + '\n  копия: ' + папка);
      const занят = spawnSync(process.execPath, [path.join(ПРОЕКТ, 'штаб', 'браузер-занят.js'), '--ждать'], { encoding: 'utf8', timeout: 1300000 });
      const р = spawnSync(process.execPath, [__filename, '--прогон', '--корень', папка, '--порт-комнат', String(ПОРТ_КОМНАТ_ЛОМ), '--порт-файлов', String(ПОРТ_ФАЙЛОВ_ЛОМ),
        '--стоп', '--снимки', path.join(папка, 'снимки')].concat(п.доводы), { encoding: 'utf8', timeout: 180000 });
      const вывод = (р.stdout || '') + (р.stderr || '');
      const первый = (вывод.match(/ПЕРВЫЙ_ПРОВАЛ: (.*)/) || [])[1] || '';
      const верно = р.status === 1 && первый.startsWith(п.ожидаемыйШаг);
      console.log('  выход: ' + р.status + ', первый провал: «' + первый + '»' + (верно ? '  → ПОКРАСНЕЛА, как и должна' : '  → ОЖИДАЛОСЬ красное на шаге «' + п.ожидаемыйШаг + '»'));
      if (!верно) console.log('  ----- вывод -----\n' + вывод.split('\n').slice(-25).join('\n'));
      if (верно) покраснело++;
      void занят;
    } catch (е) {
      console.log('  не удалось прогнать поломку: ' + е.message);
    } finally {
      fs.rmSync(папка, { recursive: true, force: true });
    }
  });
  console.log('\nПоломок: ' + ПОЛОМКИ.length + ', покраснело: ' + покраснело);
  process.exitCode = покраснело === ПОЛОМКИ.length ? 0 : 1;
}

