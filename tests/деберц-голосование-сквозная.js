/** Плашка голосования: видна ли, её слова и видимые кнопки. */
function плашка(с) {
  return с.evaluate(() => {
    const корень = document.getElementById('плашка-досрочно');
    const видим = у => {
      if (!у) return false;
      const ст = getComputedStyle(у);
      const р = у.getBoundingClientRect();
      return ст.display !== 'none' && ст.visibility !== 'hidden' && р.width > 0 && р.height > 0 && !у.classList.contains('скрыт');
    };
    const тек = к => { const у = корень && корень.querySelector('.' + к); return у && видим(у) ? у.textContent.trim() : ''; };
    const виден = Boolean(корень) && видим(корень);
    return {
      есть: Boolean(корень),
      виден,
      текст: виден ? тек('плашка-досрочно__текст') : '',
      счёт: виден ? тек('плашка-досрочно__счёт') : '',
      отсчёт: виден ? тек('плашка-досрочно__отсчёт') : '',
      подпись: виден ? тек('плашка-досрочно__подпись') : '',
      причина: виден ? тек('плашка-досрочно__причина') : '',
      кнопки: виден ? Array.from(корень.querySelectorAll('.плашка-досрочно__кнопки button')).filter(видим).map(к => к.textContent.trim()) : []
    };
  });
}
