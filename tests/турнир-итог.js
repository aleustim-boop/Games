/* ---- Подписи Telegram: свои, как в tests/турнир-сервер.js ---- */
function подписать(поля) {
  const строки = Object.keys(поля).map((к) => к + '=' + поля[к]).sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(ТОКЕН).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}
function подпись(номер, имя) {
  const поля = {
    query_id: 'AAF' + номер,
    user: JSON.stringify({ id: номер, first_name: имя }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  const всё = Object.assign({}, поля, { hash: подписать(поля) });
  return Object.keys(всё).map((к) => encodeURIComponent(к) + '=' + encodeURIComponent(всё[к])).join('&');
}

/* ---- Часы: до начала турнира ~75 с ---- */
const ДО_НАЧАЛА_МС = 75 * 1000;
let сдвиг = 0;
function сейчас() { return Date.now() + сдвиг; }
(function поставитьЧасы() {
  const день = турниры.турнирДня(Date.now());
  let цель = день.началоМс - ДО_НАЧАЛА_МС;
  if (Date.now() > цель) {
    цель = турниры.турнирДня(день.началоМс + 24 * 60 * 60 * 1000).началоМс - ДО_НАЧАЛА_МС;
  }
  сдвиг = цель - Date.now();
})();

/* ---- Страницы игры по http: настоящие файлы проекта ---- */
function запуститьРаздачуСтраниц() {
  return new Promise((готово) => {
    const с = http.createServer((запрос, ответ) => {
      let путь = '/';
      try { путь = decodeURIComponent(запрос.url.split('?')[0]); } catch (о) { /* как есть */ }
      if (путь.slice(-1) === '/') путь += 'index.html';
      const файл = path.join(КОРЕНЬ, путь);
      if (файл.indexOf(КОРЕНЬ) !== 0 || !fs.existsSync(файл) || fs.statSync(файл).isDirectory()) {
        ответ.writeHead(404); ответ.end('нет'); return;
      }
      ответ.writeHead(200, { 'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'application/octet-stream' });
      ответ.end(fs.readFileSync(файл));
    });
    с.listen(0, '127.0.0.1', () => готово(с));
  });
}

/** Дождаться, пока браузер свободен (правило проекта), и только потом запускать. */
function дождатьсяБраузера() {
  const р = childProcess.spawnSync(process.execPath, [path.join(КОРЕНЬ, 'штаб', 'браузер-занят.js'), '--ждать'], { encoding: 'utf8' });
  console.log('  браузер-занят: ' + String(р.stdout || '').trim().split('\n').pop() + ' (код ' + р.status + ')');
  return р.status === 0;
}

/** Страница игрока: своя подпись, часы как у сервера, ошибки консоли в список. */
async function открытьИгрока(браузер, номер, имя, адресСтраниц, портСервера, журнал) {
  const страница = await браузер.newPage({ viewport: { width: 390, height: 844 } });
  await подготовитьПодделку(страница, { подпись: подпись(номер, имя) });
  const сдвигСтраницы = сдвиг;
  await страница.addInitScript('(function(){var Р=Date,с=' + сдвигСтраницы + ';' +
    'function Д(){var а=arguments;if(!(this instanceof Д))return new Р(Р.now()+с).toString();' +
    'if(а.length===0)return new Р(Р.now()+с);return new (Function.prototype.bind.apply(Р,[null].concat([].slice.call(а))))();}' +
    'Д.prototype=Р.prototype;Д.now=function(){return Р.now()+с;};Д.UTC=Р.UTC;Д.parse=Р.parse;window.Date=Д;})();');
  страница.on('console', (з) => {
    const откуда = (з.location && з.location().url) || '';
    if (з.type() === 'error' && откуда.indexOf('telegram-web-app.js') !== -1) return;
    /* Фото соперника: у выдуманных игроков фото нет, сервер честно отвечает 404
       (так задумано — server/сервер.js, «/фото/»). Не ошибка игры. */
    if (з.type() === 'error' && /404/.test(з.text()) && decodeURIComponent(откуда).indexOf('/фото/') !== -1) return;
    if (з.type() === 'error') журнал.push(имя + ': ' + з.text() + (откуда ? ' @ ' + откуда : ''));
  });
  страница.on('pageerror', (о) => журнал.push(имя + ': pageerror: ' + (о && о.message)));
  // Обращение к боевому адресу 8790 — само по себе плохо: фиксируем и не пускаем.
  await страница.route(/^http:\/\/127\.0\.0\.1:8790\//, (п) => { журнал.push(имя + ': обращение к боевому порту 8790'); п.abort(); });
  await страница.goto(адресСтраниц + '/index.html?' + encodeURIComponent('сервер') + '=' +
    encodeURIComponent('http://127.0.0.1:' + портСервера) + '#' + encodeURIComponent('турнир'));
  return страница;
}

