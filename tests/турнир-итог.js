/* ---- Telegram не настоящий: любой выход к api.telegram.org — провал ---- */
const выходыВТелеграм = [];
['request', 'get'].forEach(function (имя) {
  const было = https[имя];
  https[имя] = function (первый) {
    const хост = typeof первый === 'string' ? первый : ((первый && (первый.hostname || первый.host)) || String(первый));
    if (/telegram\.org/i.test(String(хост))) {
      выходыВТелеграм.push(String(хост));
      throw new Error('проверка не пускает наружу, в настоящий Telegram: ' + хост);
    }
    return было.apply(this, arguments);
  };
});
