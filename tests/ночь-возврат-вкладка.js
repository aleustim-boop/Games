async function прогнать(исходник, порт, только) {
  const краснота = [];
  for (const имя of Object.keys(СЛУЧАИ)) {
    if (только && имя !== только) continue;
    try { await СЛУЧАИ[имя](исходник, порт); }
    catch (е) { краснота.push(имя + ': ' + (е && е.message || е)); }
  }
  return краснота;
}

/* ---------- Порча на копии ---------- */

function копияСПорчей(порча) {
  const текст = fs.readFileSync(НАСТОЯЩАЯ_СЕТЬ, 'utf8');
  // Переводы строк в порче — «\n»; подгоняем под файл (вдруг в нём \r\n).
  const перевод = текст.indexOf('\r\n') !== -1 ? '\r\n' : '\n';
  const было = порча.было.split('\n').join(перевод);
  const стало = порча.стало.split('\n').join(перевод);
  if (текст.split(было).length - 1 !== 1) return null;
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'ночь-п10-'));
  const копия = path.join(папка, 'сеть.js');
  fs.writeFileSync(копия, текст.replace(было, function () { return стало; }));
  return копия;
}

async function порчаКраснеет(порча, порт) {
  const копия = копияСПорчей(порча);
  if (!копия) { console.log('  порча ' + порча.номер + ': строка не найдена ровно один раз — ' + порча.зачем); return false; }
  const красное = await прогнать(fs.readFileSync(копия, 'utf8'), порт, порча.случай);
  const поймана = красное.some(function (с) { return с.indexOf(порча.случай + ':') === 0; });
  console.log('  порча ' + порча.номер + ' (' + порча.зачем + '): ' +
    (поймана ? 'красная, как и нужно — ' + красное[0] : 'ЗЕЛЁНАЯ — проверка не поймала порчу') + '  [копия: ' + копия + ']');
  return поймана;
}

