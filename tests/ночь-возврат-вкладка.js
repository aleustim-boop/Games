function запись(память) {
  for (const [ключ, значение] of память.ящик) {
    if (ключ.indexOf('room_') === 0) { try { return { ключ: ключ, данные: JSON.parse(значение) }; } catch (с) { return null; } }
  }
  return null;
}

async function дождаться(условие, мс) {
  const до = Date.now() + мс;
  while (Date.now() < до) { if (условие()) return true; await пауза(50); }
  return условие();
}

function ждать(условие, слова) { if (!условие) throw new Error(слова); }

/* Вкладка А создаёт стол через «Игра с другом» → «Создать игру». */
async function столВкладкиА(исходник, порт, память, эфир) {
  const а = открытьВкладку(исходник, порт, память, эфир);
  а.клик('кнопка-с-другом');
  await пауза(100);
  а.клик('кнопка-создать-игру');
  const сел = await дождаться(function () {
    const з = запись(память);
    return Boolean(з && з.данные.код && з.данные.владелец === а.имя());
  }, 5000);
  ждать(сел, 'вкладка А не создала стол (метки стола в памяти нет — ноль найденного)');
  return а;
}

