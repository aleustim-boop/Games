/* Поддельный канал между вкладками: письмо доходит до всех ДРУГИХ
   открытых каналов с тем же именем, асинхронно — как в браузере. */
function сделатьЭфир() {
  const каналы = [];
  const счёт = { вопросов: 0, держуОт: [] };   // сколько раз спросили «кто держит стол»
  const каналВкладки = function (вкладка) {
    return function Канал(имя) {
      const я = { имя: String(имя), вкладка: вкладка, слушатели: [] };
      каналы.push(я);
      this.addEventListener = function (вид, дело) { if (вид === 'message') я.слушатели.push(дело); };
      this.removeEventListener = function (вид, дело) { я.слушатели = я.слушатели.filter(function (д) { return д !== дело; }); };
      this.close = function () { я.вкладка = { закрыта: true }; };
      this.postMessage = function (данные) {
        if (данные && данные.вид === 'кто-держит') счёт.вопросов++;
        if (данные && данные.вид === 'держу') счёт.держуОт.push(вкладка);
        const текст = JSON.stringify(данные);
        for (const другой of каналы) {
          if (другой === я || другой.имя !== я.имя || другой.вкладка.закрыта || вкладка.закрыта) continue;
          setImmediate(function () {
            if (другой.вкладка.закрыта || другой.вкладка.заморожена) return;
            другой.слушатели.slice().forEach(function (дело) { дело({ data: JSON.parse(текст) }); });
          });
        }
      };
    };
  };
  каналВкладки.счёт = счёт;
  return каналВкладки;
}

/* Ломкий канал: есть, но падает — при создании или при отправке письма
   (так бывает во встроенных браузерах с урезанными правами). */
function сделатьЛомкийКанал(где) {
  return function () {
    return function Канал() {
      if (где === 'создание') throw new Error('канал между вкладками запрещён');
      this.addEventListener = function () {};
      this.removeEventListener = function () {};
      this.close = function () {};
      this.postMessage = function () { throw new Error('письмо в канал не ушло'); };
    };
  };
}

/* Срок, после которого метка считается брошенной, — из самого сеть.js. */
function срокЗанятостиМс() {
  const найдено = /const СРОК_ЗАНЯТОСТИ = ([0-9]+) [*] 1000;/.exec(fs.readFileSync(НАСТОЯЩАЯ_СЕТЬ, 'utf8'));
  if (!найдено) throw new Error('в js/сеть.js не нашлась СРОК_ЗАНЯТОСТИ (ноль найденного)');
  return Number(найдено[1]) * 1000;
}

