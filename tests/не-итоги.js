https.request = function (настройки, обработчик) {
  const куда = настройки && typeof настройки === 'object' ? String(настройки.hostname || настройки.host || '') : String(настройки || '');
  if (куда.indexOf('api.telegram.org') === -1) return настоящийЗапрос.apply(https, arguments);
  const запрос = new EventEmitter();
  запрос.setTimeout = function () { return запрос; };
  запрос.write = function () { return true; };
  запрос.destroy = function () { return запрос; };
  запрос.end = function (тело) {
    const метод = String(настройки.path || '').split('/').pop();
    let данные = {};
    try { данные = JSON.parse(String(тело || '{}')); } catch (сбой) { данные = {}; }
    ответTelegramБоту(метод, данные).then(function (итог) {
      const ответ = new EventEmitter();
      ответ.statusCode = 200;
      ответ.setEncoding = function () {};
      if (typeof обработчик === 'function') обработчик(ответ);
      ответ.emit('data', JSON.stringify(итог));
      ответ.emit('end');
    });
    return запрос;
  };
  return запрос;
};

