/** Копия server/ (без боевых данных) и js/ во временной папке, с одной порчей. */
function испорченнаяКопия(ломка) {
  const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'не-итоги-копия-'));
  const данныеПроекта = path.join(КОРЕНЬ, 'server', 'данные');
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(врем, 'server'), {
    recursive: true,
    filter: function (откуда) { return откуда !== данныеПроекта && !откуда.startsWith(данныеПроекта + path.sep); }
  });
  fs.cpSync(path.join(КОРЕНЬ, 'js'), path.join(врем, 'js'), { recursive: true });
  const файл = path.join(врем, 'server', ломка.файл);
  const текст = fs.readFileSync(файл, 'utf8').replace(/\r\n/g, '\n');
  const сколько = текст.split(ломка.было).length - 1;
  if (сколько !== 1) {
    печать('ЛОМАЮЩИЙ ПРОГОН НЕ СОСТОЯЛСЯ: в копии server/' + ломка.файл + ' нужная строка найдена ' +
      сколько + ' раз(а), а ждали ровно один.');
    fs.rmSync(врем, { recursive: true, force: true });
    process.exit(2);
  }
  fs.writeFileSync(файл, текст.split(ломка.было).join(ломка.стало), 'utf8');
  return врем;
}

