/** Ждём, пока уйдёт нужное число писем, и ещё тишину: не придёт ли лишнее. */
async function дождатьсяПисем(отметка, сколько) {
  const начало = Date.now();
  let число = письмаПосле(отметка).length;
  let перемена = начало;
  while (Date.now() - начало < 6000) {
    await пауза(20);
    const сейчас = письмаПосле(отметка).length;
    if (сейчас !== число) { число = сейчас; перемена = Date.now(); }
    if (число >= сколько && Date.now() - перемена >= 600) break;
  }
}
