(async function () {
  console.log('Письма «давно не заходили» на сервере. Порт ' + ПОРТ + ', данные в ' + ПАПКА_ДАННЫХ_ПРОВЕРКИ + '\n');
  let сбой = null;
  проверить(сервера.оснасткаДляПроверки(ТОКЕН, поддельныйTelegram) === true, 'оснастка с выдуманным ключом поставлена');
  сервера.адресИгрыДляПроверки(АДРЕС_ИГРЫ);
  const сервер = сервера.создатьСервер();
  try {
    if (!(await портСвободен(ПОРТ))) throw new Error('порт ' + ПОРТ + ' занят');
    await new Promise(function (готово, беда) {
      сервер.once('error', беда);
      сервер.listen(ПОРТ, ХОСТ, готово);
    });
    await проверитьПисьма();
  } catch (беда) {
    сбой = беда;
    console.log('СБОЙ ПРОВЕРКИ: ' + (беда && беда.message));
  }
  сервер.close();
  try { комнаты.остановитьУборку(); } catch (с) { /* не беда */ }
  сервера.оснасткаДляПроверки();
  сервера.адресИгрыДляПроверки();

  проверить(запросовВTelegram === 0, 'за весь прогон настоящих запросов в api.telegram.org — 0 (' + запросовВTelegram + ')');
  проверить(проверок >= 30, 'проверок выполнено достаточно (ноль найденного — провал): ' + проверок);

  try { fs.rmSync(ПАПКА_ДАННЫХ_ПРОВЕРКИ, { recursive: true, force: true }); } catch (с) { /* не беда */ }
  if (КОПИЯ) { try { fs.rmSync(КОПИЯ, { recursive: true, force: true }); } catch (с) { /* не беда */ } }

  console.log('\n----------------------------------------');
  for (const беда of провалы) console.log('  - ' + беда);
  console.log('Итого проверок: ' + проверок + ', провалов: ' + (провалы.length + (сбой ? 1 : 0)));
  process.exit(сбой || провалы.length > 0 ? 1 : 0);
})();
