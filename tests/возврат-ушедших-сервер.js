/** Первые 12:00 по Москве (09:00 UTC) не раньше момента t. */
function ближайшийПолдень(t) {
  const началоДня = Math.floor(t / СУТКИ) * СУТКИ;
  const полдень = началоДня + 9 * ЧАС;
  return полдень >= t ? полдень : полдень + СУТКИ;
}

