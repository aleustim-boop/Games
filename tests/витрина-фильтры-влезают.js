/** Копия style.css со СТАРЫМИ gap/padding ряда фильтров — во временной папке ОС. */
function испорченнаяКопияСтиля() {
  const путь = path.join(КОРЕНЬ, 'style.css');
  const исходник = fs.readFileSync(путь, 'utf8');
  const былGap = /gap:\s*clamp\(5px,\s*1\.5vw,\s*8px\);/;
  const былPadding = /padding:\s*0 clamp\(9px,\s*2\.6vw,\s*16px\);/;
  if (!былGap.test(исходник) || !былPadding.test(исходник)) {
    console.log('ОШИБКА: в style.css не нашлись нынешние gap/padding ряда «.витрина__фильтры» —');
    console.log('приём порчи устарел (числа поменялись сильнее, чем ждал этот тест), обновите его.');
    process.exit(2);
  }
  const испорченный = исходник
    .replace(былGap, 'gap: clamp(7px, 2.2vw, 10px);')
    .replace(былPadding, 'padding: 0 clamp(14px, 4.1vw, 18px);');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'витрина-фильтры-сломано-'));
  const путьКопии = path.join(папка, 'style.css');
  fs.writeFileSync(путьКопии, испорченный, 'utf8');
  return { папка: папка, путьКопии: путьКопии };
}

function поднятьРаздачу() {
  const сервер = http.createServer(function (запрос, ответ) {
    let путь = запрос.url.split('?')[0].split('#')[0];
    try { путь = decodeURIComponent(путь); } catch (ошибка) { /* оставим как есть */ }
    if (путь === '/') путь = '/index.html';
    const файл = path.join(КОРЕНЬ, путь.slice(1));
    if (файл.indexOf(path.join(КОРЕНЬ, 'bot')) === 0 || /[\\/]\./.test(файл.slice(КОРЕНЬ.length))) {
      ответ.writeHead(403); ответ.end('нельзя'); return;
    }
    fs.readFile(файл, function (беда, тело) {
      if (беда) { ответ.writeHead(404); ответ.end('нет такого файла'); return; }
      ответ.writeHead(200, { 'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'text/plain' });
      ответ.end(тело);
    });
  });
  return new Promise((готово) => сервер.listen(0, '127.0.0.1', () => готово(сервер)));
}

let проверок = 0;
let провалов = 0;
function проверить(условие, слова) {
  проверок++;
  if (условие) { console.log('  ок      ' + слова); return true; }
  провалов++;
  console.log('  ПЛОХО   ' + слова);
  return false;
}

/** Мерка ряда фильтров: ширина, край, и прямоугольник каждой из кнопок. */
function мераРяда(страница) {
  return страница.evaluate(function () {
    const ряд = document.querySelector('.витрина__фильтры');
    if (!ряд) return null;
    const пр = ряд.getBoundingClientRect();
    const кнопки = Array.from(document.querySelectorAll('.витрина__фильтр')).map(function (к) {
      const р = к.getBoundingClientRect();
      return { right: р.right, left: р.left, height: р.height, активна: к.getAttribute('aria-pressed') === 'true' };
    });
    return { scrollWidth: ряд.scrollWidth, clientWidth: ряд.clientWidth, right: пр.right, кнопки: кнопки };
  });
}

/** Все утверждения задания по одной мерке ряда. Возвращает мерку четвёртой кнопки (для отчёта). */
function проверитьМерку(мерка, ширина, суффикс) {
  const метка = ширина + суффикс;
  if (!проверить(Boolean(мерка), метка + ': ряд «.витрина__фильтры» нашёлся в разметке')) return null;
  проверить(мерка.кнопки.length === 4, метка + ': в ряду ровно 4 кнопки «.витрина__фильтр» (нашлось ' + мерка.кнопки.length + ')');
  проверить(мерка.scrollWidth <= мерка.clientWidth + 1,
    метка + ': ряд не прокручивается (scrollWidth=' + мерка.scrollWidth + ', clientWidth=' + мерка.clientWidth + ')');
  const четвёртая = мерка.кнопки[3];
  проверить(Boolean(четвёртая) && четвёртая.right <= мерка.right + 0.5,
    метка + ': правый край четвёртой кнопки (' + (четвёртая ? Math.round(четвёртая.right) : '—') +
    ') ≤ правого края ряда (' + Math.round(мерка.right) + ')');
  мерка.кнопки.forEach(function (к, i) {
    проверить(к.height >= 44, метка + ': кнопка №' + (i + 1) + ' высотой ≥ 44 (' + Math.round(к.height) + ')');
  });
  return { четвёртая: четвёртая, край: мерка.right };
}

(async function () {
  console.log('=== Витрина: четыре фишки-фильтра влезают без прокрутки ===');

  let врПапка = null;
  let путьИспорченногоСтиля = доводПуть;
  if (СЛОМАТЬ && !путьИспорченногоСтиля) {
    const к = испорченнаяКопияСтиля();
    врПапка = к.папка;
    путьИспорченногоСтиля = к.путьКопии;
  }
  if (СЛОМАТЬ) {
    console.log('*** ЛОМАЮЩИЙ ЗАПУСК: подсунут style.css со старыми gap/padding ряда фильтров —');
    console.log('    360 обязана покраснеть (копия: ' + путьИспорченногоСтиля + ') ***');
  }

  const раздача = await поднятьРаздачу();
  const корень = 'http://127.0.0.1:' + раздача.address().port;
  const браузер = await робот.chromium.launch();
  let сбой = null;

  try {
    for (const ширина of ШИРИНЫ) {
      const место = await браузер.newContext({ viewport: { width: ширина, height: ВЫСОТА } });
      const страница = await место.newPage();
      await робот.безTelegram(страница);
      if (СЛОМАТЬ) {
        const текстКопии = fs.readFileSync(путьИспорченногоСтиля, 'utf8');
        await робот.перехватить(страница, /\/style\.css(\?|$)/, function (путь) {
          путь.fulfill({ status: 200, contentType: 'text/css; charset=utf-8', body: текстКопии });
        });
      }
      страница.on('pageerror', function (беда) { console.log('  (ошибка страницы: ' + беда.message + ')'); });

      await страница.goto(корень + '/index.html', { waitUntil: 'load' });
      await страница.waitForTimeout(400);

      const мерка = мераРяда(страница);
      const итог = проверитьМерку(await мерка, ширина, '');

      const имяСнимка = 'витрина-фильтры-' + ширина + (СЛОМАТЬ ? '-сломано' : '') + '.png';
      await страница.screenshot({ path: path.join(папкаСнимков, имяСнимка) });
      console.log('  снимок   tests/снимки/' + имяСнимка);

      if (ширина === 360 && итог) {
        console.log('  число    360: ширина ряда (right)=' + Math.round(итог.край) +
          ', правый край 4-й кнопки=' + Math.round(итог.четвёртая.right));
      }

      /* Нажимаем «Головоломки» — та же мерка обязана остаться верной
         и для АКТИВНОЙ фишки. */
      const нажалось = await страница.evaluate(function () {
        const кн = document.querySelector('[data-фильтр="головоломки"]');
        if (!кн) return false;
        кн.click();
        return true;
      });
      проверить(нажалось, ширина + ': кнопка «Головоломки» (data-фильтр="головоломки") нашлась и нажалась');
      await страница.waitForTimeout(200);

      const меркаПосле = await мераРяда(страница);
      проверитьМерку(меркаПосле, ширина, ' (после «Головоломки»)');
      if (меркаПосле) {
        const активна = меркаПосле.кнопки[3] && меркаПосле.кнопки[3].активна;
        проверить(Boolean(активна), ширина + ': после нажатия четвёртая кнопка стала активной (aria-pressed="true")');
      }

      if (ширина === 360) {
        const имяСнимкаГ = 'витрина-фильтры-360-головоломки' + (СЛОМАТЬ ? '-сломано' : '') + '.png';
        await страница.screenshot({ path: path.join(папкаСнимков, имяСнимкаГ) });
        console.log('  снимок   tests/снимки/' + имяСнимкаГ);
      }

      await место.close();
    }
  } catch (беда) {
    сбой = беда;
  }

  await браузер.close();
  раздача.close();
  if (врПапка) { try { fs.rmSync(врПапка, { recursive: true, force: true }); } catch (е) { /* не страшно */ } }

  console.log('\n----------------------------------------');
  if (сбой) console.log('ОБОРВАЛОСЬ: ' + сбой.stack);
  console.log('Цело: ' + (проверок - провалов) + ', провалов: ' + провалов);
  process.exit(провалов === 0 && !сбой ? 0 : 1);
})();
