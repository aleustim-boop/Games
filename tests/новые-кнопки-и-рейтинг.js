'use strict';

/* =====================================================================
   НОВЫЕ КНОПКИ И ЭКРАН РЕЙТИНГА — ВМЕСТЕ, А НЕ ПО ОТДЕЛЬНОСТИ.

   За день в игру уехало много кусков, и каждый проверял свой исполнитель.
   Здесь ищем то, что видно только когда куски стоят рядом: одна половина
   ждёт одного, вторая шлёт другое, и при этом никто не падает.

   Что проверяем:
     1. «Рейтинг игроков» на экране рекордов: кнопка есть, открывает свой
        экран, «Назад» возвращает обратно;
     2. выключатель вибрации: есть, переключается, помнит выбор после
        перезагрузки, и — главное — когда выключен, игра вибрацию у Telegram
        НЕ просит (считаем просьбы поддельным Telegram);
     3. экран рейтинга вне Telegram: он обязан честно сказать, что рейтинг
        ведётся по учётной записи, а не показать пустую таблицу и не сломаться;
     4. консоль без красного во всех случаях.

   Запуск (страничный сервер уже поднят):
       node tests/новые-кнопки-и-рейтинг.js
       node tests/новые-кнопки-и-рейтинг.js 8080
   ===================================================================== */

const { chromium, подготовитьПодделку, безTelegram } = require('./браузер-робот.js');

const ПОРТ = Number(process.argv[2]) || 8080;
const АДРЕС = 'http://127.0.0.1:' + ПОРТ + '/';

let провалов = 0;

/** Нажать, если кнопка есть и видна. Нужно там, где путь стал короче:
    «Играть с ботом» теперь ведёт сразу за стол, и отдельной кнопки
    «Играть» на дороге может не быть вовсе. */
async function нажатьЕслиЕсть(страница, примета) {
  try {
    const видна = await страница.evaluate((п) => {
      const к = document.querySelector(п);
      return !!(к && к.offsetParent !== null);
    }, примета);
    if (!видна) return false;
    await страница.click(примета, { timeout: 4000 });
    return true;
  } catch (сбой) { return false; }
}
function проверить(условие, слова) {
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}

function ловецОшибок(страница) {
  const красные = [];
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
    красные.push('консоль: ' + м.text());
  });
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  return красные;
}

/** Дойти до экрана рекордов: витрина → меню → игра с ботом → «Рекорды». */
async function доРекордов(страница) {
  await страница.click('#кнопка-игра-дурак');
  await страница.waitForTimeout(250);
  await страница.click('#кнопка-рекорды');
  await страница.waitForTimeout(500);
}

/** Какой экран сейчас смотрит игрок (берём последний видимый: плашки лежат поверх). */
function видимыйЭкран(страница) {
  return страница.evaluate(() => {
    const все = document.querySelectorAll('.экран.экран--виден');
    return все.length ? все[все.length - 1].id : '(ни одного)';
  });
}

(async () => {
  const браузер = await chromium.launch();
  console.log('Новые кнопки и экран рейтинга. Страница: ' + АДРЕС);

  /* ================================================================
     1. «Рейтинг игроков» и выключатель вибрации — внутри Telegram
     ================================================================ */
  console.log('\n=== 1. Внутри Telegram: кнопки на месте и работают ===');
  {
    const окно = await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
    const страница = await окно.newPage();
    const красные = ловецОшибок(страница);
    await подготовитьПодделку(страница, { версия: '8.0', полныйЭкран: 'дают' });
    await страница.goto(АДРЕС);
    await страница.waitForTimeout(500);

    /* Сначала доходим до экрана игры с ботом: выключатели звука и вибрации
       живут там, а страница открывается на витрине игр. */
    await страница.click('#кнопка-игра-дурак');
    await страница.waitForTimeout(250);
    await страница.click('#кнопка-режим-бот');
    await страница.waitForTimeout(300);

    /* ---- выключатель вибрации ---- */
    const вибро = await страница.evaluate(() => {
      const к = document.getElementById('кнопка-вибрация');
      return к ? { есть: true, подпись: к.textContent.trim(), выключен: к.classList.contains('кнопка--выключено') } : { есть: false };
    });
    проверить(вибро.есть, 'выключатель вибрации есть на экране игры с ботом' +
      (вибро.есть ? ' («' + вибро.подпись + '»)' : ' — кнопки нет вовсе'));

    if (вибро.есть) {
      /* Считаем просьбы о вибрации до и после выключения: если выключатель
         только меняет подпись, а игра всё равно дёргает Telegram, — это
         ровно то тихое рассогласование, которое мы ищем. */
      await нажатьЕслиЕсть(страница, '#кнопка-играть');
      await страница.waitForTimeout(900);
      const послеХода = await страница.evaluate(async () => {
        const было = window.__дневник.вибраций;
        const карта = document.querySelector('#карты-человека .карта');
        if (карта) carta_click(карта);
        function carta_click(у) { у.click(); }
        await new Promise((г) => setTimeout(г, 400));
        return { было: было, стало: window.__дневник.вибраций };
      });
      console.log('  просьб о вибрации при включённой: было ' + послеХода.было + ', стало ' + послеХода.стало);
      проверить(послеХода.стало >= послеХода.было, 'счётчик вибраций не уменьшается');

      await страница.click('#кнопка-в-меню');
      await страница.waitForTimeout(300);
      const вопрос = await видимыйЭкран(страница);
      if (вопрос === 'экран-выхода') { await страница.click('#кнопка-выход-да'); await страница.waitForTimeout(400); }

      const переключили = await страница.evaluate(async () => {
        const к = document.getElementById('кнопка-вибрация');
        к.click();
        await new Promise((г) => setTimeout(г, 200));
        return {
          подпись: к.textContent.trim(),
          выключен: к.classList.contains('кнопка--выключено'),
          /* Игра хранит выбор под латинским именем «haptics» — ищем и его,
             и русские имена: стенд не должен зависеть от того, как назвали ключ. */
          память: Object.keys(localStorage)
            .filter((к2) => /вибра|haptic/i.test(к2))
            .map((к2) => к2 + '=' + localStorage.getItem(к2)).join(',')
        };
      });
      console.log('  после нажатия: «' + переключили.подпись + '», в памяти: ' + переключили.память);
      проверить(переключили.выключен, 'кнопка перешла в положение «выключено»');
      проверить(!!переключили.память, 'выбор записан в память браузера');

      // Помнит ли выбор после перезагрузки
      await страница.reload();
      await страница.waitForTimeout(600);
      await страница.click('#кнопка-игра-дурак');
      await страница.waitForTimeout(250);
      await страница.click('#кнопка-режим-бот');
      await страница.waitForTimeout(300);
      const послеПерезагрузки = await страница.evaluate(() => {
        const к = document.getElementById('кнопка-вибрация');
        return к ? { подпись: к.textContent.trim(), выключен: к.classList.contains('кнопка--выключено') } : null;
      });
      проверить(послеПерезагрузки && послеПерезагрузки.выключен,
        'после перезагрузки вибрация по-прежнему выключена («' + (послеПерезагрузки && послеПерезагрузки.подпись) + '»)');

      /* Теперь главное: при выключенной вибрации игра не должна просить её у Telegram. */
      const тишина = await страница.evaluate(async () => {
        const было = window.__дневник.вибраций;
        document.getElementById('кнопка-играть').click();
        await new Promise((г) => setTimeout(г, 900));
        const карта = document.querySelector('#карты-человека .карта');
        if (карта) карта.click();
        await new Promise((г) => setTimeout(г, 500));
        return { было: было, стало: window.__дневник.вибраций };
      });
      console.log('  просьб о вибрации при выключенной: было ' + тишина.было + ', стало ' + тишина.стало);
      проверить(тишина.стало === тишина.было,
        'выключенная вибрация и правда молчит (было ' + тишина.было + ', стало ' + тишина.стало + ')');
    }

    проверить(красные.length === 0, 'консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));
    await окно.close();
  }

  /* ================================================================
     2. Кнопка «Рейтинг игроков» на экране рекордов
     ================================================================ */
  console.log('\n=== 2. «Рейтинг игроков» открывает свой экран ===');
  {
    const окно = await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
    const страница = await окно.newPage();
    const красные = ловецОшибок(страница);
    await подготовитьПодделку(страница, { версия: '8.0', полныйЭкран: 'дают' });
    await страница.goto(АДРЕС);
    await страница.waitForTimeout(500);
    await доРекордов(страница);

    const кнопка = await страница.evaluate(() => {
      const к = document.getElementById('кнопка-рейтинг-игроков');
      if (!к) return { есть: false };
      const п = к.getBoundingClientRect();
      return { есть: true, текст: к.textContent.trim(), высота: Math.round(п.height), видна: п.height > 1 };
    });
    проверить(кнопка.есть, 'кнопка «Рейтинг игроков» есть на экране рекордов');
    if (кнопка.есть) {
      console.log('  кнопка: «' + кнопка.текст + '», высота ' + кнопка.высота);
      проверить(кнопка.высота >= 44, 'кнопка не ниже 44 точек под палец: ' + кнопка.высота);
      await страница.click('#кнопка-рейтинг-игроков');
      await страница.waitForTimeout(800);
      const экран = await видимыйЭкран(страница);
      проверить(экран === 'экран-рейтинга-игроков', 'открылся экран рейтинга игроков (сейчас «' + экран + '»)');

      const внутри = await страница.evaluate(() => {
        const э = document.getElementById('экран-рейтинга-игроков');
        return {
          текст: (э.textContent || '').replace(/\s+/g, ' ').trim().slice(0, 160),
          кнопокВыбора: э.querySelectorAll('.рейтинг-выбор .кнопка').length
        };
      });
      console.log('  на экране: «' + внутри.текст + '»');
      проверить(внутри.текст.length > 10, 'экран не пустой — человеку есть что прочитать');
      проверить(внутри.кнопокВыбора >= 2, 'есть выбор игры (кнопок ' + внутри.кнопокВыбора + ')');

      await страница.click('#кнопка-рейтинг-игроков-назад');
      await страница.waitForTimeout(500);
      const назад = await видимыйЭкран(страница);
      проверить(назад === 'экран-рекордов' || назад === 'экран-рейтинга',
        '«Назад» вернул откуда пришли (сейчас «' + назад + '»)');
    }
    проверить(красные.length === 0, 'консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));
    await окно.close();
  }

  /* ================================================================
     3. Экран рейтинга вне Telegram — самое опасное место
     ================================================================ */
  console.log('\n=== 3. Тот же экран в обычном браузере, без Telegram ===');
  {
    const окно = await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
    const страница = await окно.newPage();
    const красные = ловецОшибок(страница);
    await безTelegram(страница);          // подделку не кладём вовсе
    await страница.goto(АДРЕС);
    await страница.waitForTimeout(600);
    await доРекордов(страница);

    const есть = await страница.evaluate(() => !!document.getElementById('кнопка-рейтинг-игроков'));
    console.log('  кнопка «Рейтинг игроков» вне Telegram: ' + (есть ? 'есть' : 'её нет'));

    if (есть) {
      await страница.click('#кнопка-рейтинг-игроков');
      await страница.waitForTimeout(800);
      const что = await страница.evaluate(() => {
        const э = document.getElementById('экран-рейтинга-игроков');
        const таблица = document.getElementById('таблица-рейтинга-игроков') || э.querySelector('.таблица');
        return {
          экран: (document.querySelectorAll('.экран.экран--виден')[document.querySelectorAll('.экран.экран--виден').length - 1] || {}).id,
          текст: (э.textContent || '').replace(/\s+/g, ' ').trim(),
          строк: таблица ? таблица.querySelectorAll('.таблица__строка').length : -1
        };
      });
      console.log('  экран «' + что.экран + '», строк в таблице ' + что.строк);
      console.log('  текст: «' + что.текст.slice(0, 200) + '»');
      /* Главное: человеку объяснили, почему рейтинга нет, а не показали пустоту. */
      проверить(/учётн|Telegram|войти|аккаунт|через/i.test(что.текст),
        'вне Telegram экран объясняет, что рейтинг ведётся по учётной записи');
      проверить(что.текст.length > 20, 'экран не пустой');
    } else {
      /* Кнопки нет — это тоже честный ответ, но тогда человек не должен
         оставаться без объяснения на самом экране рекордов. */
      const наРекордах = await страница.evaluate(() =>
        (document.getElementById('экран-рекордов').textContent || '').replace(/\s+/g, ' ').trim());
      console.log('  на экране рекордов: «' + наРекордах.slice(0, 200) + '»');
      проверить(true, 'кнопки нет вовсе — вне Telegram рейтинг не предлагают (так тоже честно)');
    }
    проверить(красные.length === 0, 'консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));
    await окно.close();
  }

  await браузер.close();
  console.log('\nИтог: провалов ' + провалов);
  process.exit(провалов ? 1 : 0);
})().catch((о) => { console.error('Стенд упал: ' + (о && о.stack || о)); process.exit(2); });
