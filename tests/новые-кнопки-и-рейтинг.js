      await страница.waitForTimeout(600);
      await вЛобби(страница);
      await открытьЛист(страница);
      await страница.waitForTimeout(200);
      const послеПерезагрузки = await снятьВибро();
      проверить(послеПерезагрузки.слово === 'выкл' && послеПерезагрузки.отмечено === 'false',
        'после перезагрузки вибрация по-прежнему выключена («' + послеПерезагрузки.слово + '»)');
      await страница.evaluate(() => закрытьЛистИгры(false));

      /* Теперь главное: при выключенной вибрации игра не должна просить её у Telegram. */
      const былоВибраций = await страница.evaluate(() => window.__дневник.вибраций);
