/**
 * Дверь /рейтинг подделываем по-настоящему, а не заглушкой: js/рейтинг-
 * экран.js кладёт в тело запроса «initData» (js/рейтинг-экран.js,
 * «подписьTelegram» — window.Telegram.WebApp.initData) — внутри
 * Telegram (подготовитьПодделку) она непустая, вне Telegram (безTelegram)
 * её вовсе нет. Сервер по ней и решает «узналиВас»; наш перехватчик
 * повторяет это решение: initData есть → «узналиВас:true» с честными
 * данными, initData нет → «узналиВас:false» — только тогда игра
 * показывает «Рейтинг ведётся по учётной записи Telegram» (раздел 3).
 * Ответ «ок:true, узналиВас:true» всегда (независимо от initData) —
 * прежняя ошибка тестировщика: раздел 3 получал чужие имена вместо
 * ожидаемого объяснения про Telegram. Фоновый шум трёх других дверей
 * (/статистика, /пульс, /мой-аватар) — тихое {ок:false}, тот же приём,
 * что в tests/браузер-рейтинг-круг-друзей.js.
 */
async function перехватитьСеть(страница) {
  await перехватить(страница, /\/(?:рейтинг(?:\?|$)|статистика(?:\?|$)|пульс(?:\?|$)|мой-аватар(?:\?|$))/,
    function (путь, запрос, адрес) {
      if (!/\/рейтинг(?:\?|$)/.test(адрес || '')) {
        путь.fulfill({ status: 200, contentType: 'application/json; charset=utf-8', body: JSON.stringify({ ок: false }) });
        return;
      }
      let игра = 'дурак';
      let initData = '';
      try {
        const тело = JSON.parse((запрос.postData && запрос.postData()) || '{}');
        if (тело && тело.игра) игра = тело.игра;
        if (тело && typeof тело.initData === 'string') initData = тело.initData;
      } catch (о) { /* тела может не быть */ }
      if (!initData) {
        путь.fulfill({
          status: 200, contentType: 'application/json; charset=utf-8',
          body: JSON.stringify({ ок: true, узналиВас: false, игра: игра })
        });
        return;
      }
      путь.fulfill({
        status: 200, contentType: 'application/json; charset=utf-8',
        body: JSON.stringify({
          ок: true, узналиВас: true, игра: игра, всего: 8, яВТаблице: true, я: ВОКРУГ_ПОДДЕЛЬНЫЙ[1],
          верхушка: ВЕРХУШКА_ПОДДЕЛЬНАЯ, вокругМеня: ВОКРУГ_ПОДДЕЛЬНЫЙ, сила: null,
          друзья: { естьДрузья: false, верхушка: [], вокругМеня: [], всего: 0 }
        })
      });
    });
}

