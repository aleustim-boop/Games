/* ======================================================================
   ЛОМАЮЩИЙ ПРОГОН (--сломать-порт): не гоняем весь тяжёлый сценарий из
   4 игр × 2 ширин заново — довольно одной страницы (дурак, 390×844, тот
   же случай, где обычный прогон в чистом виде и находил отказ к 8790),
   чтобы проверить именно фильтр: краснеет ли «ошибки в консоли», когда
   отказ идёт на ДРУГОЙ порт, а не на настоящий 8790.
   ====================================================================== */
async function главнаяЛомающаяПорт() {
  console.log('=== Обход «Завершить партию»: ЛОМАЮЩИЙ прогон --сломать-порт (проверяем сам фильтр 8790, стенд ' + АДРЕС + ') ===\n');

  const чужойПорт = await свободныйПорт();
  const испорченнаяСеть = создатьИспорченнуюСеть(чужойПорт);
  console.log('Подменяю в браузере js/сеть.js (route) на копию: АДРЕС_ПО_УМОЛЧАНИЮ смотрит на 127.0.0.1:' + чужойПорт + ' вместо настоящего 8790 (порт закрыт, слушать его никто не будет).');
  console.log('Ожидаю: фильтр «:8790/» не простит отказ к ЭТОМУ порту — «ошибки в консоли» у дурака обязаны покраснеть.\n');

  const браузер = await chromium.launch();
  try {
    const { контекст, страница, красные } = await новаяСтраница(браузер, 'index.html', 390, 844, null, испорченнаяСеть);
    try {
      // Простого открытия витрины мало — запрос «моё место» (js/дурак-
      // путь.js: освежитьЛобби → fetch адрес+'/рейтинг') уходит только
      // при показе ЛОББИ дурака, не раньше. Заходим в лобби так же, как
      // это делает перейтиВЛоббиДурака в tests/финальная-проверка-
      // кнопок-назад.js.
      await страница.locator('#кнопка-игра-дурак').click({ timeout: 5000 });
      await страница.waitForSelector('#экран-лобби.экран--виден', { timeout: 5000 }).catch(() => null);
      // Первый прогон показал гонку: fetch к чужому порту иногда не
      // успевает отработать за 1.5с (то ERR_NETWORK_CHANGED сразу, то
      // вообще ничего за это время) — опрашиваем красные короткими
      // порциями до 6с вместо одной фиксированной паузы.
      for (let попытка = 0; попытка < 12 && красные.length === 0; попытка++) {
        await страница.waitForTimeout(500);
      }
      записатьНаходки('дурак', '390x844 (порт подменён на ' + чужойПорт + ')', 'ошибки в консоли', красные);
    } finally {
      await контекст.close().catch(() => null);
    }
  } finally {
    await браузер.close().catch(() => null);
  }

  console.log('');
  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
  if (провалов === 0) {
    console.log('\nЛОМАЮЩИЙ ЗАПУСК (порт) ПРОВАЛЕН: фильтр «:8790/» проглотил отказ к чужому порту — проверка слепая, ловит не то, что нужно.');
    process.exit(1);
  }
  console.log('\nЛомающий запуск (порт) успешен: фильтр не глотает отказ к чужому адресу — «ошибки в консоли» честно покраснели.');
  process.exit(0);
}

if (сломатьПорт) {
  главнаяЛомающаяПорт().catch((ошибка) => {
    console.error('Обход «Завершить партию» (ломающий порт) упал: ' + (ошибка && ошибка.stack || ошибка));
    process.exit(2);
  });
} else {
  главная().catch((ошибка) => {
    console.error('Обход «Завершить партию» упал: ' + (ошибка && ошибка.stack || ошибка));
    process.exit(2);
  });
}
