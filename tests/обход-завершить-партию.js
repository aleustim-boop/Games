/** Единая точка учёта булевых проверок — печатает и красит итог. */
function проверить(игра, ширина, имя, условие, детали) {
  проверок++;
  if (условие) {
    console.log('  ок    — ' + игра + ' ' + ширина + ': ' + имя);
    return true;
  }
  провалов++;
  const строка = 'ПЛОХО — ' + игра + ' ' + ширина + ': ' + имя + (детали ? ' (' + детали + ')' : '');
  console.log(строка);
  находки.push(строка);
  return false;
}

function записатьНаходки(игра, ширина, описаниеКатегории, список) {
  проверок++;
  if (!список.length) {
    console.log('  ок    — ' + игра + ' ' + ширина + ': ' + описаниеКатегории + ' — не найдено');
    return;
  }
  провалов++;
  список.forEach((деталь) => {
    const строка = 'ПЛОХО — ' + игра + ' ' + ширина + ': ' + описаниеКатегории + ' — ' + деталь;
    console.log(строка);
    находки.push(строка);
  });
}

function провалКрахом(игра, ширина, ошибка) {
  проверок++; провалов++;
  const строка = 'ПЛОХО — ' + игра + ' ' + ширина + ': проверка упала — ' + (ошибка && ошибка.message || ошибка);
  console.log(строка);
  находки.push(строка);
}

async function убедитьсяЧтоУзелЕсть(страница, игра, ширина, селектор, описание) {
  const найден = await страница.$(селектор).catch(() => null);
  return проверить(игра, ширина, 'узел «' + описание + '» найден (' + селектор + ')', Boolean(найден));
}

async function кликНеЗависая(страница, игра, ширина, селектор, описание) {
  try {
    await страница.click(селектор, { timeout: ТАЙМАУТ_ДЕЙСТВИЯ });
    return true;
  } catch (ошибка) {
    проверить(игра, ширина, 'клик по «' + описание + '» удался (' + селектор + ')', false,
      'не дождался: ' + (ошибка && ошибка.message ? ошибка.message.split('\n')[0] : ошибка));
    return false;
  }
}

/* ---------------------------------------------------------------------
   ЛОМАЮЩИЙ РЕЖИМ: испорченная копия js/лист-ещё.js в памяти — только
   функция «спроситьЗавершить» заменена на «return false» — счётчиком
   фигурных скобок от сигнатуры (regex «\b» кириллицу не понимает,
   да и всё тело функции всё равно неудобно ловить одним выражением).
   --------------------------------------------------------------------- */
function создатьИспорченныйЛистЕщё() {
  const оригинал = fs.readFileSync(ПУТЬ_ЛИСТА_ЕЩЁ, 'utf8');
  const маркер = 'function спроситьЗавершить() {';
  const начало = оригинал.indexOf(маркер);
  if (начало === -1) {
    throw new Error('Ломающий прогон: в js/лист-ещё.js не нашлась сигнатура «' + маркер + '» — ' +
      'похоже, функцию переименовали, поломку в этом тесте нужно поправить вслед за ней.');
  }
  let глубина = 0;
  let конец = -1;
  for (let i = начало + маркер.length - 1; i < оригинал.length; i++) {
    const символ = оригинал[i];
    if (символ === '{') глубина++;
    else if (символ === '}') {
      глубина--;
      if (глубина === 0) { конец = i; break; }
    }
  }
  if (конец === -1) {
    throw new Error('Ломающий прогон: не нашёл конец функции «спроситьЗавершить» — не сошлись фигурные скобки.');
  }
  return оригинал.slice(0, начало) +
    'function спроситьЗавершить() { return false; /* испорчено ломающим прогоном tests/обход-завершить-партию.js */ }' +
    оригинал.slice(конец + 1);
}

/* ---------------------------------------------------------------------
   ЛОМАЮЩИЙ РЕЖИМ (порт): испорченная копия js/сеть.js в памяти — адрес
   сервера комнат по умолчанию подменён с 8790 на другой, заведомо
   закрытый порт. Проверяет не игру, а сам фильтр 8790 в новаяСтраница().
   --------------------------------------------------------------------- */
function создатьИспорченнуюСеть(чужойПорт) {
  const путьСети = path.join(КОРЕНЬ, 'js', 'сеть.js');
  const оригинал = fs.readFileSync(путьСети, 'utf8');
  const было = "const АДРЕС_ПО_УМОЛЧАНИЮ = 'http://127.0.0.1:8790';";
  if (оригинал.indexOf(было) === -1) {
    throw new Error('Ломающий прогон --сломать-порт: в js/сеть.js не нашлась строка «' + было + '» — ' +
      'адрес по умолчанию переехал, поправьте испортитель вслед за ним.');
  }
  return оригинал.replace(было, "const АДРЕС_ПО_УМОЛЧАНИЮ = 'http://127.0.0.1:" + чужойПорт + "';");
}

/** Свободный сейчас порт — сразу закрываем пробный сервер, слушать на нём
 * дальше никто не будет, так что браузер гарантированно получит отказ. */
function свободныйПорт() {
  return new Promise((решить, отклонить) => {
    const пробник = net.createServer();
    пробник.on('error', отклонить);
    пробник.listen(0, '127.0.0.1', () => {
      const порт = пробник.address().port;
      пробник.close(() => решить(порт));
    });
  });
}

/* ---------------------------------------------------------------------
   Открытие страницы: без Telegram-подделки (кнопки «⋯»/«‹» верхней
   строки скрыты style.css внутри Telegram-режима — нужна браузерная
   раскладка, как её видит человек вне Telegram). Ломающий прогон
   подменяет /js/лист-ещё.js на лету через route(), настоящий файл не трогая.
   --------------------------------------------------------------------- */
async function новаяСтраница(браузер, файл, ширина, высота, испорченныйЛист, испорченнаяСеть) {
  const контекст = await браузер.newContext({ viewport: { width: ширина, height: высота }, hasTouch: true });
  const страница = await контекст.newPage();

  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const т = м.text();
    const откуда = (м.location() && м.location().url) || '';
    if (/telegram-web-app\.js|telegram\.org/.test(т) || /telegram-web-app\.js|telegram\.org/.test(откуда)) return;
    /* Дурак опрашивает рекорды/рейтинг на боевом порту сервера комнат
       (js/сеть.js, АДРЕС_ПО_УМОЛЧАНИЮ = 'http://127.0.0.1:8790') — на
       этом стенде такого сервера нет и поднимать его здесь нельзя (порт
       8790 трогать запрещено). Отказ подключения к НЕМУ — ожидаемая
       часть сценария «сервер недоступен», не поломка страницы (тот же
       приём, что в tests/кнопки-назад-везде.js и tests/финальная-
       проверка-кнопок-назад.js). Фильтруем по САМОМУ АДРЕСУ (порт в
       «откуда»), а не по всем ERR_CONNECTION_REFUSED подряд — иначе
       отказ к другому, настоящему адресу проехал бы тем же путём и
       спрятал бы реальную поломку (см. --сломать-порт ниже). */
    if (/:8790\//.test(откуда) && /ERR_CONNECTION_REFUSED/.test(т)) return;
    красные.push('консоль: ' + т);
  });
  страница.on('requestfailed', (з) => {
    const адресЗапроса = з.url();
    if (/telegram-web-app\.js|telegram\.org/.test(адресЗапроса)) return;
    const отказ = (з.failure() && з.failure().errorText) || '';
    if (/:8790\//.test(адресЗапроса) && /ERR_CONNECTION_REFUSED/.test(отказ)) return;
    красные.push('сеть: ' + адресЗапроса + ' — ' + отказ);
  });

  // Порчи листа и сети не бывает разом (два независимых ломающих прогона
  // --сломать / --сломать-порт) — перехватить() регистрирует свой
  // page.route('**/*', …), и второй такой вызов на той же странице тихо
  // отберёт все запросы у первого (playwright отдаёт их последнему
  // зарегистрированному), поэтому веточки ниже строго взаимоисключающие.
  if (испорченнаяСеть) {
    await перехватить(страница, /\/сеть\.js(?:\?|$)/, (route) => route.fulfill({
      status: 200, contentType: 'text/javascript; charset=utf-8', body: испорченнаяСеть
    }));
  } else if (испорченныйЛист !== null) {
    await перехватить(страница, /\/лист-ещё\.js(?:\?|$)/, (route) => route.fulfill({
      status: 200, contentType: 'text/javascript; charset=utf-8', body: испорченныйЛист
    }));
  } else {
    await безTelegram(страница);
  }

  await страница.goto(АДРЕС + '/' + файл);
  await страница.waitForTimeout(700);

  return { контекст, страница, красные };
}

/* ---------------------------------------------------------------------
   НАДЁЖНЫЙ СНИМОК — приём и декодер PNG скопированы без изменений
   логики из tests/обход-игр.js (см. там подробное объяснение гонки
   «screenshot раньше, чем Chromium дорисовал кадр после resize»).
   --------------------------------------------------------------------- */
const ПОРОГ_МАКС_ЯРКОСТИ = 200;
const ПОПЫТОК_СНИМКА_МАКС = 4;

function decodePNG(буфер) {
  if (буфер.length < 8 || буфер.readUInt32BE(0) !== 0x89504e47) throw new Error('не похоже на PNG (нет сигнатуры)');
  let смещение = 8;
  let ширина = 0, высота = 0, битГлубина = 0, типЦвета = 0;
  const idatЧасти = [];
  while (смещение + 8 <= буфер.length) {
    const длина = буфер.readUInt32BE(смещение);
    const тип = буфер.toString('ascii', смещение + 4, смещение + 8);
    const данные = буфер.subarray(смещение + 8, смещение + 8 + длина);
    if (тип === 'IHDR') {
      ширина = данные.readUInt32BE(0); высота = данные.readUInt32BE(4);
      битГлубина = данные.readUInt8(8); типЦвета = данные.readUInt8(9);
    } else if (тип === 'IDAT') {
      idatЧасти.push(данные);
    } else if (тип === 'IEND') {
      break;
    }
    смещение += 8 + длина + 4;
  }
  if (битГлубина !== 8) throw new Error('ожидался PNG с 8 битами на канал, получено ' + битГлубина);
  const каналов = { 0: 1, 2: 3, 4: 2, 6: 4 }[типЦвета];
  if (!каналов) throw new Error('неподдержанный тип цвета PNG: ' + типЦвета + ' (палитра не разбирается)');
  const сырые = zlib.inflateSync(Buffer.concat(idatЧасти));
  const байтСтроки = ширина * каналов;
  const пиксели = Buffer.alloc(высота * байтСтроки);
  let вход = 0;
  let предыдущаяСтрока = Buffer.alloc(байтСтроки);
  for (let y = 0; y < высота; y++) {
    const типФильтра = сырые[вход]; вход++;
    const строка = сырые.subarray(вход, вход + байтСтроки);
    вход += байтСтроки;
    const результат = Buffer.alloc(байтСтроки);
    for (let x = 0; x < байтСтроки; x++) {
      const raw = строка[x];
      const a = x >= каналов ? результат[x - каналов] : 0;
      const b = предыдущаяСтрока[x];
      const c = x >= каналов ? предыдущаяСтрока[x - каналов] : 0;
      let значение;
      if (типФильтра === 0) значение = raw;
      else if (типФильтра === 1) значение = raw + a;
      else if (типФильтра === 2) значение = raw + b;
      else if (типФильтра === 3) значение = raw + Math.floor((a + b) / 2);
      else if (типФильтра === 4) {
        const p = a + b - c;
        const pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c);
        значение = raw + (pa <= pb && pa <= pc ? a : (pb <= pc ? b : c));
      } else throw new Error('неизвестный тип фильтра строки PNG: ' + типФильтра);
      результат[x] = значение & 0xff;
    }
    результат.copy(пиксели, y * байтСтроки);
    предыдущаяСтрока = результат;
  }
  return { ширина, высота, каналов, пиксели };
}

function яркостьСнимка(буфер) {
  const { ширина, высота, каналов, пиксели } = decodePNG(буфер);
  const шаг = 3;
  let макс = 0;
  for (let y = 0; y < высота; y += шаг) {
    for (let x = 0; x < ширина; x += шаг) {
      const idx = (y * ширина + x) * каналов;
      const яркость = 0.299 * пиксели[idx] + 0.587 * пиксели[idx + 1] + 0.114 * пиксели[idx + 2];
      if (яркость > макс) макс = яркость;
    }
  }
  return { максЯркость: макс };
}

async function снятьСнимокНадёжно(страница) {
  let буфер = null, метрика = { максЯркость: 0 }, ошибкаРазбора = null;
  for (let попытка = 1; попытка <= ПОПЫТОК_СНИМКА_МАКС; попытка++) {
    await страница.evaluate(() => new Promise((готово) => requestAnimationFrame(() => requestAnimationFrame(готово))));
    буфер = await страница.screenshot();
    try {
      метрика = яркостьСнимка(буфер);
      ошибкаРазбора = null;
    } catch (е) {
      ошибкаРазбора = е;
      break;
    }
    if (метрика.максЯркость >= ПОРОГ_МАКС_ЯРКОСТИ) return { буфер, метрика, попыток: попытка, ошибкаРазбора: null };
    await страница.waitForTimeout(250 * попытка);
  }
  return { буфер, метрика, попыток: ПОПЫТОК_СНИМКА_МАКС, ошибкаРазбора };
}

/* ---------------------------------------------------------------------
   Шаг 1: сесть за стол с ботом самым быстрым путём из лобби.
   --------------------------------------------------------------------- */
async function начатьПартиюСБотом(страница, игра, ширина) {
  if (игра.дурак) {
    try {
      await сестьЗаСтол(страница);
    } catch (ошибка) {
      проверить(игра.имя, ширина, 'партия дурака началась (сестьЗаСтол по трём шагам)', false, ошибка.message);
      return false;
    }
    const виден = await страница.evaluate((id) => {
      const э = document.getElementById(id);
      return Boolean(э && э.classList.contains('экран--виден'));
    }, игра.экранСтола);
    return проверить(игра.имя, ширина, 'партия началась (виден #' + игра.экранСтола + ')', виден);
  }

  await страница.waitForSelector('#экран-лобби.экран--виден', { timeout: ТАЙМАУТ_ДЕЙСТВИЯ }).catch(() => null);
  if (!await убедитьсяЧтоУзелЕсть(страница, игра.имя, ширина, '#лобби-боты', 'кнопка «Играть с ботом»')) return false;
  if (!await кликНеЗависая(страница, игра.имя, ширина, '#лобби-боты', 'кнопка «Играть с ботом»')) return false;
  if (!await пройтиШагБота(страница, игра, ширина)) return false;
  const доска = await страница.waitForSelector('#' + игра.экранСтола + '.экран--виден', { timeout: 15000 }).catch(() => null);
  return проверить(игра.имя, ширина, 'партия началась (виден #' + игра.экранСтола + ')', Boolean(доска));
}

/* ---------------------------------------------------------------------
   Общий помощник: у шашек/нард/шахмат «Играть с ботом» открывает ВТОРОЙ
   шаг (уровень уже выбран по умолчанию) с отдельной кнопкой начала —
   раньше партия начиналась сразу по клику первой карточки (задание
   24.09, лобби переделали по эталону дурака). Оба узла обязаны
   найтись — отсутствие это честный провал, а не тихий пропуск.
   --------------------------------------------------------------------- */
async function пройтиШагБота(страница, игра, ширина) {
  const шаг = игра.ботШаг2;
  if (!проверить(игра.имя, ширина, 'у игры задан второй шаг бота (ботШаг2)', Boolean(шаг))) return false;
  const шагПоявился = await страница.waitForSelector('#' + шаг.экран + '.экран--виден', { timeout: ТАЙМАУТ_ДЕЙСТВИЯ }).catch(() => null);
  if (!проверить(игра.имя, ширина, 'второй шаг бота открылся (#' + шаг.экран + ')', Boolean(шагПоявился))) return false;
  if (!await убедитьсяЧтоУзелЕсть(страница, игра.имя, ширина, '#' + шаг.кнопкаНачать, 'кнопка начала на втором шаге бота')) return false;
  if (!await кликНеЗависая(страница, игра.имя, ширина, '#' + шаг.кнопкаНачать, 'кнопка начала на втором шаге бота')) return false;
  return true;
}

/* ---------------------------------------------------------------------
   Полный сценарий (шаги 2–7) для одной игры на одной ширине.
   --------------------------------------------------------------------- */
async function пройтиИгру(браузер, игра, размер, испорченныйЛист) {
  const ширинаМетка = размер.width + 'x' + размер.height;
  const { контекст, страница, красные } = await новаяСтраница(браузер, игра.файл, размер.width, размер.height, испорченныйЛист);
  try {
    // 1. Начать партию с ботом
    if (!await начатьПартиюСБотом(страница, игра, ширинаМетка)) return;
    await страница.waitForTimeout(500);

    // 2. Открыть «⋯» → строка «Завершить партию» → нажать
    if (!await убедитьсяЧтоУзелЕсть(страница, игра.имя, ширинаМетка, '#кнопка-игра-ещё', 'кнопка «⋯» на столе')) return;
    if (!await кликНеЗависая(страница, игра.имя, ширинаМетка, '#кнопка-игра-ещё', 'кнопка «⋯»')) return;
    const листОткрылся = await страница.waitForSelector('#лист-игры:not(.скрыт)', { timeout: ТАЙМАУТ_ДЕЙСТВИЯ }).catch(() => null);
    if (!проверить(игра.имя, ширинаМетка, 'лист «⋯» открылся после клика «⋯»', Boolean(листОткрылся))) return;
    await страница.waitForTimeout(400); // гонка transition листа (~200–300мс)

    const подпись = await страница.textContent('#кнопка-лист-игры-меню .лист-ещё__подпись').catch(() => null);
    проверить(игра.имя, ширинаМетка, 'строка листа называется «Завершить партию»',
      подпись === 'Завершить партию', 'получил: ' + JSON.stringify(подпись));

    if (!await кликНеЗависая(страница, игра.имя, ширинаМетка, '#кнопка-лист-игры-меню', 'строка «Завершить партию»')) return;
    const плашкаЧерезСтроку = await страница.waitForSelector('#плашка-завершить:not(.скрыт)', { timeout: ТАЙМАУТ_ДЕЙСТВИЯ }).catch(() => null);
    проверить(игра.имя, ширинаМетка, 'плашка «Завершить партию?» открылась по клику строки листа', Boolean(плашкаЧерезСтроку));
    const листЗакрытПослеСтроки = await страница.evaluate(() => {
      const л = document.getElementById('лист-игры');
      return Boolean(л && л.classList.contains('скрыт'));
    });
    проверить(игра.имя, ширинаМетка, 'лист «⋯» закрылся, когда открылась плашка', листЗакрытПослеСтроки);
    const кнопкиПлашкиОк = await страница.evaluate(() => {
      const п = document.getElementById('плашка-завершить');
      if (!п) return false;
      const нет = п.querySelector('.плашка-завершить__нет');
      const да = п.querySelector('.плашка-завершить__да');
      return Boolean(нет && да && нет.offsetParent !== null && да.offsetParent !== null);
    });
    проверить(игра.имя, ширинаМетка, 'обе кнопки плашки видны («Вернуться к игре» и «Завершить»)', кнопкиПлашкиОк);

    // 3. «Вернуться к игре»
    if (!await кликНеЗависая(страница, игра.имя, ширинаМетка, '.плашка-завершить__нет', '«Вернуться к игре»')) return;
    await страница.waitForTimeout(250);
    const плашкаСкрытаПослеНет = await страница.evaluate(() => {
      const п = document.getElementById('плашка-завершить');
      return Boolean(п && п.classList.contains('скрыт'));
    });
    проверить(игра.имя, ширинаМетка, 'плашка скрылась после «Вернуться к игре»', плашкаСкрытаПослеНет);
    const листВсёЕщёЗакрытПослеНет = await страница.evaluate(() => {
      const л = document.getElementById('лист-игры');
      return Boolean(л && л.classList.contains('скрыт'));
    });
    проверить(игра.имя, ширинаМетка, 'лист «⋯» остался закрыт после «Вернуться к игре»', листВсёЕщёЗакрытПослеНет);
    const столНаМесте = await страница.evaluate((id) => {
      const э = document.getElementById(id);
      return Boolean(э && э.classList.contains('экран--виден'));
    }, игра.экранСтола);
    проверить(игра.имя, ширинаМетка, 'стол партии на месте после «Вернуться к игре»', столНаМесте);

    // 4а. Лист «⋯» ЗАКРЫТ (обычное состояние во время партии) — настоящий
    // клик мышью/пальцем по «‹» на столе должен открыть плашку напрямую,
    // через листЕщё.спроситьЗавершить(), без строки листа.
    if (!await убедитьсяЧтоУзелЕсть(страница, игра.имя, ширинаМетка, игра.кнопкаНазадСтол, 'кнопка «‹» на столе')) return;
    if (!await кликНеЗависая(страница, игра.имя, ширинаМетка, игра.кнопкаНазадСтол, 'кнопка «‹» на столе (лист закрыт)')) return;
    await страница.waitForTimeout(350);

    const плашкаПослеЗакрытогоЛиста = await страница.evaluate(() => {
      const п = document.getElementById('плашка-завершить');
      return Boolean(п && !п.classList.contains('скрыт'));
    });
    проверить(игра.имя, ширинаМетка,
      'плашка «Завершить партию?» открылась по «‹» на столе (лист «⋯» закрыт, настоящий клик)', плашкаПослеЗакрытогоЛиста);

    if (плашкаПослеЗакрытогоЛиста) {
      // Плашка появилась — но это ещё не значит, что она появилась НАД
      // столом: партия не должна обрываться сама по себе, пока игрок не
      // подтвердил выход. Стол обязан остаться на экране под плашкой.
      const столПодПлашкойНаМесте = await страница.evaluate((id) => {
        const э = document.getElementById(id);
        return Boolean(э && э.classList.contains('экран--виден'));
      }, игра.экранСтола);
      проверить(игра.имя, ширинаМетка,
        'стол партии остался на экране ПОД плашкой (клик «‹» не оборвал партию раньше подтверждения)', столПодПлашкойНаМесте);
      if (!столПодПлашкойНаМесте) {
        const путьСнимкаБага = path.join(ПАПКА_СНИМКОВ, игра.имя + '-' + размер.width + '.png');
        const { буфер: буферБага } = await снятьСнимокНадёжно(страница);
        fs.writeFileSync(путьСнимкаБага, буферБага);
        console.log('  инфо  — ' + игра.имя + ' ' + ширинаМетка + ': партия уже потеряна раньше подтверждения — дальше в этой партии 4б не проверить; ' +
          'снимок (плашка висит поверх лобби, партии уже нет) сохранён в ' + path.basename(путьСнимкаБага));
        return;
      }

      // Закрыть плашку «Вернуться к игре», чтобы честно, с чистого стола, проверить путь 4б.
      if (!await кликНеЗависая(страница, игра.имя, ширинаМетка, '.плашка-завершить__нет', '«Вернуться к игре» (после 4а)')) return;
      await страница.waitForTimeout(250);
      const столНаМестеПослеНет4а = await страница.evaluate((id) => {
        const э = document.getElementById(id);
        return Boolean(э && э.classList.contains('экран--виден'));
      }, игра.экранСтола);
      проверить(игра.имя, ширинаМетка,
        'стол партии на месте после «Вернуться к игре» (путь через «‹», лист был закрыт)', столНаМестеПослеНет4а);
      if (!столНаМестеПослеНет4а) {
        console.log('  инфо  — ' + игра.имя + ' ' + ширинаМетка + ': после «Вернуться к игре» стола больше нет — дальше 4б не проверить, см. находку выше');
        return;
      }
    } else {
      // При --сломать у дурака вместо новой плашки всплывает СТАРЫЙ диалог
      // «#экран-выхода» — если так, закрыть и его, иначе он перекроет шаг 4б.
      const старыйДиалогОткрыт = await страница.evaluate(() => {
        const э = document.getElementById('экран-выхода');
        return Boolean(э && э.classList.contains('экран--виден'));
      });
      if (старыйДиалогОткрыт) {
        console.log('  инфо  — ' + игра.имя + ' ' + ширинаМетка + ': вместо новой плашки открылся старый «Выйти в меню?» — закрываю «Продолжить партию», это ожидаемо при --сломать');
        await кликНеЗависая(страница, игра.имя, ширинаМетка, '#кнопка-выход-нет', '«Продолжить партию» (старый диалог, после 4а)');
        await страница.waitForTimeout(250);
      } else {
        // У шашек/шахмат/нард при --сломать спроситьЗавершить()===false не
        // просто не открывает плашку — код продолжает обычный путь и молча
        // уводит со стола БЕЗ вопроса. Тогда стола (и кнопки «⋯») больше
        // нет — шаг 4б в этой партии физически не проверить, честно это
        // фиксируем и не пытаемся продолжать вслепую.
        const столВсёЕщёНаМесте = await страница.evaluate((id) => {
          const э = document.getElementById(id);
          return Boolean(э && э.classList.contains('экран--виден'));
        }, игра.экранСтола);
        if (!столВсёЕщёНаМесте) {
          console.log('  инфо  — ' + игра.имя + ' ' + ширинаМетка + ': после «‹» (лист закрыт) партия молча покинута БЕЗ вопроса — так ведёт себя поломка спроситьЗавершить() у этой игры; шаг 4б пропускаю, стола больше нет');
          return;
        }
      }
    }

    // 4б. Лист «⋯» ОТКРЫТ — программный клик по той же кнопке (el.click(),
    // без hit-теста вёрстки) — так же, как это делает системная кнопка
    // «назад» Telegram: она не элемент страницы и не завязана на затемнение
    // листа. Проверяем именно код: спроситьЗавершить() обязан сам закрыть
    // лист и открыть плашку.
    if (!await кликНеЗависая(страница, игра.имя, ширинаМетка, '#кнопка-игра-ещё', 'кнопка «⋯» (для проверки 4б)')) return;
    await страница.waitForSelector('#лист-игры:not(.скрыт)', { timeout: ТАЙМАУТ_ДЕЙСТВИЯ }).catch(() => null);
    await страница.waitForTimeout(400);

    await страница.evaluate((селектор) => {
      const э = document.querySelector(селектор);
      if (э) э.click();
    }, игра.кнопкаНазадСтол);
    await страница.waitForTimeout(350);

    const плашкаЧерезНазад = await страница.evaluate(() => {
      const п = document.getElementById('плашка-завершить');
      return Boolean(п && !п.classList.contains('скрыт'));
    });
    проверить(игра.имя, ширинаМетка,
      'плашка «Завершить партию?» открылась по «‹» на столе (лист «⋯» открыт, программный клик — как системная кнопка Telegram)', плашкаЧерезНазад);
    const листЗакрытПослеНазад = await страница.evaluate(() => {
      const л = document.getElementById('лист-игры');
      return Boolean(л && л.classList.contains('скрыт'));
    });
    проверить(игра.имя, ширинаМетка, 'лист «⋯» закрылся, когда «‹» открыла плашку', листЗакрытПослеНазад);

    if (плашкаЧерезНазад) {
      const путьСнимка = path.join(ПАПКА_СНИМКОВ, игра.имя + '-' + размер.width + '.png');
      const { буфер, метрика, попыток, ошибкаРазбора } = await снятьСнимокНадёжно(страница);
      fs.writeFileSync(путьСнимка, буфер);
      if (ошибкаРазбора) {
        провалКрахом(игра.имя, ширинаМетка, new Error('снимок сохранён, но не разобрался как PNG: ' + ошибкаРазбора.message));
      } else {
        проверить(игра.имя, ширинаМетка,
          'снимок плашки не пустой/недорисованный (максЯркость=' + Math.round(метрика.максЯркость) + ' из 255, порог ' + ПОРОГ_МАКС_ЯРКОСТИ + ')',
          метрика.максЯркость >= ПОРОГ_МАКС_ЯРКОСТИ, 'попыток снять: ' + попыток + ', файл ' + path.basename(путьСнимка));
      }
    } else {
      console.log('  инфо  — ' + игра.имя + ' ' + ширинаМетка + ': плашка через «‹» не открылась — снимок не снимаю, см. провал выше');
    }

    // 5. «Завершить» — только если плашка реально открыта (иначе кнопки в ней нет)
    if (плашкаЧерезНазад) {
      if (!await кликНеЗависая(страница, игра.имя, ширинаМетка, '.плашка-завершить__да', 'кнопка «Завершить»')) return;
      const столУшёл = await страница.waitForFunction((id) => {
        const э = document.getElementById(id);
        return !э || !э.classList.contains('экран--виден');
      }, игра.экранСтола, { timeout: 6000 }).catch(() => null);
      проверить(игра.имя, ширинаМетка, 'стол покинут после «Завершить» (#' + игра.экранСтола + ' больше не виден)', Boolean(столУшёл));
      await страница.waitForTimeout(300);
      const плашкаПропала = await страница.evaluate(() => {
        const п = document.getElementById('плашка-завершить');
        return !п || п.classList.contains('скрыт');
      });
      проверить(игра.имя, ширинаМетка, 'плашки больше нет после «Завершить»', плашкаПропала);
      const видимыйЭкран = await страница.evaluate(() => {
        const э = document.querySelector('.экран.экран--виден');
        return э ? э.id : '';
      });
      проверить(игра.имя, ширинаМетка, 'после «Завершить» виден какой-то экран (лобби/меню)', Boolean(видимыйЭкран), 'видимый экран: ' + видимыйЭкран);

      // 6. «‹» вне партии — если у этого экрана она есть.
      const узелНазадВне = await страница.$(игра.кнопкаНазадВнеПартии).catch(() => null);
      if (!узелНазадВне) {
        console.log('  инфо  — ' + игра.имя + ' ' + ширинаМетка + ': кнопки «‹» вне партии на экране «' + видимыйЭкран + '» не нашлось — пропускаю пункт 6, как разрешено заданием');
      } else {
        const видима = await узелНазадВне.isVisible().catch(() => false);
        if (!видима) {
          console.log('  инфо  — ' + игра.имя + ' ' + ширинаМетка + ': кнопка «‹» вне партии нашлась, но не видна на экране «' + видимыйЭкран + '» — пропускаю пункт 6');
        } else {
          const клик6 = await узелНазадВне.click({ timeout: 5000 }).then(() => true).catch((е) => {
            проверить(игра.имя, ширинаМетка, 'клик «‹» вне партии удался', false, е.message);
            return false;
          });
          if (клик6) {
            await страница.waitForTimeout(300);
            const плашкаНеПоявиласьВне = await страница.evaluate(() => {
              const п = document.getElementById('плашка-завершить');
              return !п || п.classList.contains('скрыт');
            });
            проверить(игра.имя, ширинаМетка, '«‹» вне партии НЕ открыла плашку «Завершить партию?»', плашкаНеПоявиласьВне);
          }
        }
      }
    } else {
      console.log('  инфо  — ' + игра.имя + ' ' + ширинаМетка + ': плашка через «‹» не открылась — пропускаю пункты 5 и 6 (ожидаемо при --сломать)');
    }

    // 7. Ошибки в консоли
    записатьНаходки(игра.имя, ширинаМетка, 'ошибки в консоли', красные);
  } catch (ошибка) {
    провалКрахом(игра.имя, ширинаМетка, ошибка);
  } finally {
    await контекст.close().catch(() => null);
  }
}

/* ---------------------------------------------------------------------
   Самопроверка ломающего прогона: шаг 4 обязан покраснеть у ВСЕХ 4 игр —
   не нашлось поломки хотя бы у одной, значит проверка не различает
   поломку, ей нельзя доверять (правило штаба «ноль найденного — провал»).
   --------------------------------------------------------------------- */
function самопроверкаЛомающего() {
  console.log('\n=== Самопроверка ломающего прогона: путь 4а («‹», лист ЗАКРЫТ — всегда достижим) обязан покраснеть у ВСЕХ 4 игр ===');
  let всеПокраснели = true;
  for (const игра of ИГРЫ) {
    const нашли4а = находки.some((строка) => строка.indexOf('ПЛОХО — ' + игра.имя + ' ') === 0 &&
      строка.indexOf('лист «⋯» закрыт, настоящий клик') !== -1);
    const нашли4б = находки.some((строка) => строка.indexOf('ПЛОХО — ' + игра.имя + ' ') === 0 &&
      строка.indexOf('лист «⋯» открыт, программный клик') !== -1);
    if (нашли4а) {
      console.log('  ок    — ' + игра.имя + ': путь 4а покраснел, как и ожидалось при поломке' +
        (нашли4б ? '; путь 4б тоже покраснел' : '; путь 4б не дошёл до проверки — поломка увела со стола раньше (молчаливый уход), это ожидаемо у этой игры'));
    } else {
      всеПокраснели = false;
      console.log('  ПЛОХО — ' + игра.имя + ': ЛОМАЮЩИЙ ПРОГОН НЕ ПОКРАСНЕЛ КАК ОЖИДАЛОСЬ на пути 4а — среди находок нет провала ' +
        '«… лист «⋯» закрыт, настоящий клик» для этой игры. Проверке нельзя доверять.');
    }
  }
  проверок++;
  if (!всеПокраснели) {
    провалов++;
    находки.push('ЛОМАЮЩИЙ ЗАПУСК НЕ ПОКРАСНЕЛ КАК ОЖИДАЛОСЬ хотя бы у одной игры — см. подробности выше');
  } else {
    console.log('  все 4 игры дали ожидаемый провал пути 4а — ломающий прогон действительно ловит поломку.');
  }
}

