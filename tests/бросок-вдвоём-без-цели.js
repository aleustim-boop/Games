'use strict';

/* =====================================================================
   БРОСОК ПРЕДМЕТА ВДВОЁМ: ЦЕЛЬ НЕ НАЗЫВАЮТ — И НЕ НАДО.

   Что ловит эта проверка.

   Живой игрок пожаловался: «не могу кинуть в друга по сети». Разбор
   показал вот что. За столом на двоих игра зовёт соперника своим
   внутренним именем ('бот'), номера кресла у неё нет вовсе — сервер его
   наружу не отдаёт. Поэтому в запросе поля «цель» не было, а сервер
   отвечал «Выберите, в кого бросить», хотя выбирать было не из кого.
   Смайлики и фразы при этом уходили нормально: им цель не нужна.

   Теперь сервер вдвоём выводит цель сам — из того, что видит за столом.
   Со слов игрока он её по-прежнему не берёт.

   ДВЕ ПОЛОВИНЫ, и вторая здесь так же важна, как первая:

     1. вдвоём бросок без цели ПРИНИМАЕТСЯ, и второй игрок видит его
        у себя с признаком «в меня»;
     2. за столом на четверых такой же бросок ОТКЛОНЯЕТСЯ прежними
        словами — там выбор есть, и делать его за игрока сервер не должен.

   Без второй половины проверка была бы зелёной «на всякий случай»:
   она прошла бы и в том случае, если сервер начнёт принимать броски
   без цели вообще всегда.

   Запуск:
       node tests/бросок-вдвоём-без-цели.js
       node tests/бросок-вдвоём-без-цели.js 8894

   Число — порт для проверочного сервера комнат (по умолчанию 8894).
   Свой порт нужен потому, что 8765 и 8790 на машине владельца бывают
   заняты чужими программами, и стук туда молча уходит в никуда.
   ===================================================================== */

const http = require('http');
const path = require('path');

const ПОРТ = Number(process.argv[2] || 8894);
const сервер = require(path.join(__dirname, '..', 'server', 'сервер.js'));
const игра = require(path.join(__dirname, '..', 'js', 'game.js'));

/* Броски — последняя треть общего списка знаков: сперва смайлики,
   потом фразы, потом предметы. Номер первого предмета считаем так же,
   как считает игра, — второй копии числа не заводим. */
const ПЕРВЫЙ_БРОСОК = игра.ЭМОЦИИ.length + игра.ФРАЗЫ.length;

/* Сервер держит паузу между бросками одного игрока. Ждать её целиком
   в проверке незачем: каждый бросок делаем от РАЗНОГО игрока. */

const провалы = [];

function проверить(что, условие, подробности) {
  if (условие) {
    console.log('  ок: ' + что);
    return;
  }
  провалы.push(что + (подробности ? ' — ' + подробности : ''));
  console.log('  ПРОВАЛ: ' + что + (подробности ? ' — ' + подробности : ''));
}

/** Один запрос к серверу комнат. Отвечает разобранным ответом. */
function спросить(путь, тело) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: '127.0.0.1', port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        try {
          готово(JSON.parse(текст || '{}'));
        } catch (ошибка) {
          готово({ сырое: текст.slice(0, 200) });
        }
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

/** Собрать комнату и посадить в неё столько игроков, сколько просят. */
async function собратьСтол(сколько) {
  const создание = await спросить('/создать', { имя: 'Игрок 1', мест: сколько });
  const код = создание.код;
  const игроки = [{ имя: 'Игрок 1', пропуск: создание.пропуск }];
  for (let номер = 2; номер <= сколько; номер++) {
    const вход = await спросить('/войти', { код: код, имя: 'Игрок ' + номер });
    игроки.push({ имя: 'Игрок ' + номер, пропуск: вход.пропуск });
  }
  return { код: код, игроки: игроки };
}

/* ---------------------------------------------------------------------
   Сами проверки
   --------------------------------------------------------------------- */

async function вдвоёмБезЦелиДоходит() {
  console.log('1. Вдвоём: бросок без цели должен дойти');
  const стол = await собратьСтол(2);
  const ответ = await спросить('/ход', {
    код: стол.код, пропуск: стол.игроки[0].пропуск,
    действие: 'эмоция', номер: ПЕРВЫЙ_БРОСОК
  });
  проверить('сервер принял бросок без цели', ответ.принято === true,
            'ответил: ' + JSON.stringify(ответ.причина));

  /* И главное — что предмет ДОЛЕТЕЛ. Приняли и потеряли — это тоже
     поломка, и жалуются игроки именно на неё, а не на код ответа. */
  const второй = await спросить('/что-нового', {
    код: стол.код, пропуск: стол.игроки[1].пропуск, версия: 0
  });
  const знак = второй.состояние && второй.состояние.знакВнимания;
  проверить('второй игрок видит бросок', Boolean(знак) && знак.номер === ПЕРВЫЙ_БРОСОК,
            'пришло: ' + JSON.stringify(знак));
  проверить('и видит, что кинули в него', Boolean(знак) && знак.вМеня === true,
            'пришло: ' + JSON.stringify(знак));
}

async function вчетверомБезЦелиОтклоняется() {
  console.log('2. Вчетвером: бросок без цели должен быть отклонён');
  const стол = await собратьСтол(4);
  const ответ = await спросить('/ход', {
    код: стол.код, пропуск: стол.игроки[0].пропуск,
    действие: 'эмоция', номер: ПЕРВЫЙ_БРОСОК
  });
  проверить('сервер отклонил бросок без цели', ответ.принято === false,
            'ответил: ' + JSON.stringify(ответ));
  проверить('и объяснил словами', Boolean(ответ.причина),
            'причина: ' + JSON.stringify(ответ.причина));
}

async function вчетверомСЦельюДоходит() {
  console.log('3. Вчетвером: бросок с названной целью доходит');
  const стол = await собратьСтол(4);
  const ответ = await спросить('/ход', {
    код: стол.код, пропуск: стол.игроки[0].пропуск,
    действие: 'эмоция', номер: ПЕРВЫЙ_БРОСОК, цель: 'Игрок 3'
  });
  проверить('сервер принял бросок в названного игрока', ответ.принято === true,
            'ответил: ' + JSON.stringify(ответ.причина));
}

async function вдвоёмВСебяНельзя() {
  console.log('4. Вдвоём: в себя бросать по-прежнему нельзя');
  const стол = await собратьСтол(2);
  const ответ = await спросить('/ход', {
    код: стол.код, пропуск: стол.игроки[0].пропуск,
    действие: 'эмоция', номер: ПЕРВЫЙ_БРОСОК, цель: 'Игрок 1'
  });
  проверить('сервер отклонил бросок в самого себя', ответ.принято === false,
            'ответил: ' + JSON.stringify(ответ));
}

async function главное() {
  /* Свой сервер поднимаем сами и на своём порту: чужой, уже запущенный,
     мог бы оказаться другой сборки, и проверка врала бы про неё. */
  const слуга = сервер.создатьСервер();
  await new Promise(function (готово) { слуга.listen(ПОРТ, '127.0.0.1', готово); });
  try {
    await вдвоёмБезЦелиДоходит();
    await вчетверомБезЦелиОтклоняется();
    await вчетверомСЦельюДоходит();
    await вдвоёмВСебяНельзя();
  } finally {
    if (слуга && typeof слуга.close === 'function') слуга.close();
    else if (typeof слуга === 'function') слуга();
  }

  console.log('');
  if (провалы.length === 0) {
    console.log('ИТОГ: бросок вдвоём доходит, а за большим столом цель по-прежнему спрашивают.');
    process.exit(0);
  }
  console.log('ИТОГ: провалов ' + провалы.length);
  for (const провал of провалы) console.log('  — ' + провал);
  process.exit(1);
}

главное().catch(function (беда) {
  console.log('Проверка сорвалась: ' + (беда && беда.message ? беда.message : беда));
  process.exit(1);
});
