/* Решение владельца 30.09: до первой взятки чужие комбинации уходят игроку только
   названием (без масти, старшей карты и очков), свои — целиком; после сбора первой
   взятки (и в окне показа комбинаций перед сбором) — целиком у всех.
   Тем же решением поле «бонусы» до первой взятки — нули у всех мест (в том числе у своего):
   бонус — итог сравнения «чья комбинация старше» и подсказал бы старшую карту соперника.
   Запуск:  node tests/деберц-комбинации-до-первой-взятки.js
   Ломающие запуски портят КОПИЮ серверного файла во временной папке:
     --сломать <путь-к-копии> [1..9]   собрать испорченную копию и прогнать на ней (должно упасть)
     --самопроверка                    прогнать все поломки и убедиться, что каждая краснеет
   Не проверено здесь: экран игры/деберц/деберц-экран.js (тексты «старше у соперника», «нужна взятка»).
   tests/поддельный-браузер.js не разбирает html и не тянет страницу деберца целиком, поэтому
   экран смотрит браузерная проверка (см. отчёт этапа). */
