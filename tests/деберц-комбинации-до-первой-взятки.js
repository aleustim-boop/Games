const П = require('../игры/деберц/деберц-правила.js');
const И = require(серверныйМодуль);

let проверок = 0;
function проверить(условие, текст) { проверок++; assert(условие, текст); }
function равно(а, б, текст) { проверок++; assert.deepEqual(а, б, текст); }

let зерно = 7;
const случайно = () => ((зерно = (Math.imul(зерно, 1664525) + 1013904223) >>> 0) / 4294967296);
const имена = ['а', 'б', 'в', 'г'];
const итогиПоРежимам = {};

// Все объекты внутри значения — поиск по всему виду, а не по одному полю.
function объектыВнутри(значение, найдено = []) {
  if (Array.isArray(значение)) значение.forEach(x => объектыВнутри(x, найдено));
  else if (значение && typeof значение === 'object') {
    найдено.push(значение); Object.values(значение).forEach(x => объектыВнутри(x, найдено));
  }
  return найдено;
}

function проверитьВиды(п, скрыто, режим) {
  const n = п.игроки.length, комбинации = п.игра.объявления;
  const всего = комбинации.reduce((с, список) => с + список.length, 0);
  for (let v = 0; v < n; v++) {
    const вид = И.видДляИгрока(п, имена[v]);
    const объекты = объектыВнутри(вид);
    const своих = комбинации[v].length;
    // Названия есть у всех комбинаций — и у своих, и у чужих.
    проверить(объекты.filter(о => 'название' in о).length === всего, 'Названия всех комбинаций на месте и нигде больше не дублируются');
    if (скрыто) {
      // Ключи «верх», «масть» вместе с «название», «очки», «вес» — только у своих комбинаций, во всём JSON.
      проверить(объекты.filter(о => 'название' in о && ('верх' in о || 'масть' in о || 'очки' in о)).length === своих,
        'До первой взятки масть, старшая карта и очки — только у своих комбинаций');
      проверить(объекты.filter(о => 'верх' in о).length === своих, 'Ключ «верх» встречается только у своих');
      проверить(!объекты.some(о => 'вес' in о), 'Ключ «вес» наружу не уходит');
    }
    // Бонусы: до открытия — нули у всех мест (и у своего), после — настоящие, в порядке «я первым».
    const настоящие = Array.from({ length: n }, (_, i) => п.игра.бонусы[(v + i) % n]);
    if (скрыто) {
      равно(вид.деберц.бонусы, настоящие.map(() => 0), 'До первой взятки бонусы — нули у всех мест');
      if (настоящие.some(Boolean)) итогиПоРежимам[режим].скрытыхБонусов++;
    } else {
      равно(вид.деберц.бонусы, настоящие, 'После открытия бонусы настоящие');
      if (настоящие.some(Boolean)) итогиПоРежимам[режим].открытыхБонусов++;
    }
    for (let о = 0; о < n; о++) {
      const отн = (о - v + n) % n, ушло = вид.деберц.объявления[отн];
      равно(ушло.length, комбинации[о].length, 'Число комбинаций сохранено');
      комбинации[о].forEach((к, k) => {
        const своя = о === v;
        if (!своя && скрыто) { равно(ушло[k], { название: к.название }, 'Чужая комбинация — только название'); итогиПоРежимам[режим].закрытых++; }
        else {
          равно(ушло[k], { название: к.название, очки: к.очки, масть: к.масть, верх: к.верх },
            своя ? 'Своя комбинация — целиком' : 'После первой взятки чужая комбинация — целиком');
          if (своя) итогиПоРежимам[режим].своих++; else итогиПоРежимам[режим].открытых++;
        }
      });
    }
  }
}

function ходить(п, действие, дополнение = {}) {
  const результат = И.сделатьХод(п, п.игроки[п.игра.ход], { действие, ...дополнение });
  проверить(результат.принято, 'Ход принят сервером: ' + (результат.причина || ''));
}

function сыгратьПартию(режим) {
  const n = режим === '2x2' ? 4 : Number(режим);
  const п = И.раздать(null, { игроки: имена.slice(0, n), парами: режим === '2x2' });
  п.игра = П.создать(случайно, 301, true, режим);
  const г = п.игра;
  ходить(п, 'торг', { масть: П.вариантыКозыря(г)[0] });
  if (г.фаза !== 'игра' || !г.объявления.some(список => список.length)) return false;
  проверитьВиды(п, true, режим);                      // сразу после выбора козыря
  for (let i = 0; i < n; i++) {
    const можно = П.доступные(г, г.ход);
    ходить(п, 'карта', { id: можно[Math.floor(случайно() * можно.length)].id });
    проверитьВиды(п, г.фаза === 'игра', режим);        // в окне показа (фаза «взятка») — уже целиком
  }
  проверить(г.фаза === 'взятка', 'Взятка разыграна и ждёт сбора');
  ходить(п, 'взятка');
  проверитьВиды(п, false, режим);                     // первая взятка собрана
  const можно = П.доступные(г, г.ход);
  ходить(п, 'карта', { id: можно[0].id });
  проверитьВиды(п, false, режим);
  return true;
}

// Партия до конца первой раздачи: выбран козырь, все взятки разыграны и собраны.
// Возвращает п, если в первой раздаче были комбинации, иначе null.
function доКонцаПервойРаздачи(режим) {
  const n = режим === '2x2' ? 4 : Number(режим);
  const п = И.раздать(null, { игроки: имена.slice(0, n), парами: режим === '2x2' });
  п.игра = П.создать(случайно, 301, true, режим);
  ходить(п, 'торг', { масть: П.вариантыКозыря(п.игра)[0] });
  if (п.игра.фаза !== 'игра') return null;
  while (!['итог', 'конец'].includes(п.игра.фаза)) {
    if (п.игра.фаза === 'взятка') { ходить(п, 'взятка'); continue; }
    const можно = П.доступные(п.игра, п.игра.ход);
    ходить(п, 'карта', { id: можно[Math.floor(случайно() * можно.length)].id });
  }
  return п.игра.фаза === 'итог' ? п : null;
}

// (б) Вторая раздача подряд: комбинации снова закрыты до её первой взятки, потом открываются.
// Сервер сдаёт вторую раздачу через Math.random — на время сдачи подменяем его нашим зерном (повторяемость).
function сыгратьВторуюРаздачу(режим) {
  const п = доКонцаПервойРаздачи(режим);
  if (!п) return false;
  const былСлучайный = Math.random;
  Math.random = случайно;
  try { ходить(п, 'раздача'); } finally { Math.random = былСлучайный; }
  const г = п.игра;
  проверить(г.номер === 2, 'Это вторая раздача подряд');
  ходить(п, 'торг', { масть: П.вариантыКозыря(г)[0] });
  if (г.фаза !== 'игра' || !г.объявления.some(список => список.length)) return false;
  проверитьВиды(п, true, режим);
  итогиПоРежимам[режим].вторыхРаздач++;
  const n = п.игроки.length;
  for (let i = 0; i < n; i++) {
    const можно = П.доступные(г, г.ход);
    ходить(п, 'карта', { id: можно[Math.floor(случайно() * можно.length)].id });
    проверитьВиды(п, г.фаза === 'игра', режим);
  }
  ходить(п, 'взятка');
  проверитьВиды(п, false, режим);
  return true;
}

// (в) «Сдаться» посреди первой взятки: фаза «конец», всё открыто у всех.
function сдатьсяПосредиПервойВзятки(режим) {
  const n = режим === '2x2' ? 4 : Number(режим);
  const п = И.раздать(null, { игроки: имена.slice(0, n), парами: режим === '2x2' });
  п.игра = П.создать(случайно, 301, true, режим);
  ходить(п, 'торг', { масть: П.вариантыКозыря(п.игра)[0] });
  if (п.игра.фаза !== 'игра' || !п.игра.объявления.some(список => список.length)) return false;
  const можно = П.доступные(п.игра, п.игра.ход);
  ходить(п, 'карта', { id: можно[0].id });
  проверить(п.игра.фаза === 'игра' && п.игра.стол.length === 1 && п.игра.взятки.every(x => x === 0), 'Сдаёмся посреди первой взятки');
  проверитьВиды(п, true, режим);                       // до сдачи — ещё закрыто
  const результат = И.сделатьХод(п, п.игроки[n - 1], { действие: 'сдаться' });
  проверить(результат.принято, 'Сдача принята сервером');
  проверить(п.игра.фаза === 'конец' && п.завершена, 'После «сдаться» партия закончена');
  for (let v = 0; v < n; v++) проверить(И.видДляИгрока(п, имена[v]).деберц.фаза === 'конец', 'Игрок видит фазу «конец»');
  проверитьВиды(п, false, режим);                      // всё открыто
  итогиПоРежимам[режим].сдач++;
  return true;
}

for (const режим of ['2', '3', '4', '2x2']) {
  итогиПоРежимам[режим] = { партий: 0, закрытых: 0, открытых: 0, своих: 0, скрытыхБонусов: 0, открытыхБонусов: 0, вторыхРаздач: 0, сдач: 0 };
  for (let попытка = 0; попытка < 400 && итогиПоРежимам[режим].партий < 8; попытка++) {
    if (сыгратьПартию(режим)) итогиПоРежимам[режим].партий++;
  }
  for (let попытка = 0; попытка < 400 && итогиПоРежимам[режим].вторыхРаздач < 4; попытка++) сыгратьВторуюРаздачу(режим);
  for (let попытка = 0; попытка < 400 && итогиПоРежимам[режим].сдач < 4; попытка++) сдатьсяПосредиПервойВзятки(режим);
  // Ноль найденных комбинаций — провал проверки, а не пропуск.
  const и = итогиПоРежимам[режим];
  проверить(и.партий >= 8, 'Режим ' + режим + ': не нашлось партий с комбинациями');
  проверить(и.закрытых > 0, 'Режим ' + режим + ': не встретилось ни одной чужой закрытой комбинации');
  проверить(и.открытых > 0, 'Режим ' + режим + ': не встретилось ни одной открытой чужой комбинации');
  проверить(и.своих > 0, 'Режим ' + режим + ': не встретилось ни одной своей комбинации');
  // Чтобы «нули до первой взятки» что-то доказывали, настоящий бонус должен был быть ненулевым.
  проверить(и.скрытыхБонусов > 0, 'Режим ' + режим + ': не встретилось закрытого вида с настоящим ненулевым бонусом');
  проверить(и.открытыхБонусов > 0, 'Режим ' + режим + ': не встретилось открытого вида с ненулевым бонусом');
  проверить(и.вторыхРаздач >= 4, 'Режим ' + режим + ': не нашлось вторых раздач с комбинациями');
  проверить(и.сдач >= 4, 'Режим ' + режим + ': не нашлось сдач посреди первой взятки с комбинациями');
}
console.log('Деберц: чужие комбинации до первой взятки — только названием, свои и после взятки — целиком; ' + JSON.stringify(итогиПоРежимам));
console.log('Итого проверок: ' + проверок + ', провалов: 0');
