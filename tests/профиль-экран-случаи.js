/**
 * Поднять экран в поддельном браузере с подделками соседних дверей.
 * настройки: { ответы: [ответ мойПрофиль, …], безРейтинга, имя, серия }.
 */
function поднятьПрофиль(настройки) {
  const н = настройки || {};
  const поднятый = бр.поднять(исходник, { имяФайла: 'общее/js/профиль-экран.js' });
  const счёт = { мойПрофиль: 0, открыть: [], открытьСчёт: [], полосы: [], стрелки: 0, возвраты: 0, наградыСпросили: 0, приглашения: [] };
  const ответы = (н.ответы || []).slice();

  if (!н.безРейтинга) {
    поднятый.окно.ЭкранРейтинга = {
      мойПрофиль: function () {
        счёт.мойПрофиль += 1;
        // Последний ответ повторяется, если запросов больше, чем заготовок.
        const ответ = ответы.length > 1 ? ответы.shift() : ответы[0];
        return Promise.resolve(ответ === undefined ? null : ответ);
      },
      игры: реестрИгр,
      открыть: function (ключ) { счёт.открыть.push(ключ); },
      открытьСчёт: function (игра) { счёт.открытьСчёт.push(игра); }
    };
  }

  /* Блок «Позвать друга»: подделка window.Награды (настоящую проверяет
     tests/награды-клиент.js). н.награды = { друзей, следующая }; друзей
     null — сервер молчит. Объект общий: проверка меняет его между открытиями. */
  if (н.награды) {
    const состояние = н.награды;
    поднятый.окно.Награды = {
      обновить: function () { счёт.наградыСпросили += 1; return Promise.resolve(состояние.друзей); },
      сколькоДрузей: function () { return состояние.друзей; },
      следующая: function () { return состояние.следующая || null; },
      есть: function () { return false; },
      наСобытие: function () { return function () {}; }
    };
  }
  /* Дверь приглашения, которую зовёт кнопка (настоящая — общее/js/похвастаться.js). */
  if (!н.безПриглашения) {
    поднятый.окно.Сеть = {
      пригласитьВПриложение: function () {
        счёт.приглашения.push(Array.prototype.slice.call(arguments));
        return Promise.resolve({ отправлено: false, способ: 'нет' });
      }
    };
  }

  поднятый.окно.Телеграм = {
    имяИгрока: function () { return н.имя === undefined ? 'Алексей Петров' : н.имя; },
    фотоИгрока: function () { return ''; },
    показатьСтрелку: function () { счёт.стрелки += 1; return true; },
    вернутьПрежнююСтрелку: function () { счёт.возвраты += 1; }
  };

  поднятый.окно.Рейтинг = {
    серияДней: function () {
      return Promise.resolve(н.серия === undefined ? { серия: 3, лучшая: 5, сегодняОтмечен: true } : н.серия);
    }
  };

  /* Полосы вкладок может и не быть: на разных страницах порядок
     подключения файлов разный, а набор «профиль» заводит другой этап. */
  if (!н.безВкладок) {
    поднятый.окно.НижниеВкладки = {
      заполнитьПолосу: function (nav) { счёт.полосы.push(nav.getAttribute('data-вкладки')); }
    };
  }

  /* Экран, с которого «пришли»: без него «‹» возвращать некуда. */
  const лобби = поднятый.документ.createElement('section');
  лобби.id = 'экран-лобби';
  лобби.className = 'экран экран--виден';
  поднятый.документ.body.appendChild(лобби);

  поднятый.счёт = счёт;
  return поднятый;
}

/** Строки блока очков на экране. */
function строкиОчков(поднятый) {
  return Array.prototype.slice.call(поднятый.документ.querySelectorAll('.профиль-очки__строка'));
}

/** Число из текста узла: «24 985» → 24985 (пробел тысяч неразрывный). */
function числоИзТекста(текст) {
  const цифры = String(текст || '').replace(/[^0-9-]/g, '');
  return цифры === '' ? null : Number(цифры);
}

function текстУзла(поднятый, селектор) {
  const узел = поднятый.документ.querySelector(селектор);
  return узел ? узел.textContent : null;
}

