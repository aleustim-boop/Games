#!/usr/bin/env node
'use strict';

/* =====================================================================
   СРОЧНАЯ ЗАПИСЬ СИЛЫ: вторая мера рейтинга должна лечь на диск сразу
   после партии, а не через пять секунд.

   Ровно та же беда, что чинилась в server/рейтинг.js (см. tests/срочная-
   запись-рейтинга.js), нашлась и в server/сила-игроков.js: партия меняла
   силу в памяти, а на диск падала отложенно (ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ = 5000).
   Штаб указал: сила на экране рейтинга показана ПЕРВОЙ, накопительные
   очки — второй кнопкой, так что чинить только очки и оставить силу
   как есть — значит защитить то, что игрок видит вторым, и бросить то,
   что он видит первым.

   ПОЧЕМУ ЗДЕСЬ НЕТ РАЗДЕЛЕНИЯ «ВАЖНОЕ / МЕЛОЧЬ», в отличие от очков.
   В накопительном рейтинге бывает партия с нулевой ценой (лёгкий бот,
   исчерпанный суточный потолок) — число на экране в этом случае и
   вправду не меняется, такую мелочь можно отложить. У силы единственное
   место, где вообще взводится запись (конец «учесть» в сила-игроков.js),
   срабатывает только когда партия дала хотя бы одно валидное сравнение —
   а оно ВСЕГДА двигает саму силу, счётчик партий и текст «последняяПартия».
   Случая «партия сыграна, но видимо ничего не изменилось» здесь нет,
   поэтому исправление — «пишем всегда сразу», без деления.

   КАК ПРОВЕРЯЕМ «упало сразу после партии» — тем же приёмом, что и для
   очков: партия засчитывается в ОТДЕЛЬНОМ процессе node, который сразу
   после сила.учесть(...) завершается через process.exit(0), без вызова
   дописать(). Если запись была синхронной (writeFileSync успел
   отработать до exit) — файл силы на диске есть. Если код вернулся
   к старой отложенной схеме — writeFileSync не успел, файла нет вовсе.

   ЧТО ПРОВЕРЯЕМ: партия двух живых людей (один победил) — сразу после
   «падения» процесса на диске уже лежат обновлённые сила и счётчик
   партий обоих игроков.

   УМЕЕТ ЛИ ОНА КРАСНЕТЬ. node tests/срочная-запись-силы.js --сломать
   берёт временную копию server/сила-игроков.js и подменяет тело
   записатьСрочно() на пятисекундный setTimeout (.unref(), как было
   раньше) — ровно та регрессия, от которой предостерегал штаб. На такой
   копии проверка обязана провалиться: сразу после «падения» файла силы
   ещё не будет.

   Боевых данных не касается: копия server/ и папка данных — во временных
   каталогах (mkdtempSync), партия считается в отдельном дочернем
   процессе node.

   Запуск:
     node tests/срочная-запись-силы.js             (обычный прогон)
     node tests/срочная-запись-силы.js --сломать   (обязан провалиться)
   Выход 0 — провалов нет, 1 — провал (смотреть строки «ПРОВАЛ» в выводе).
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const СЛОМАТЬ = process.argv.includes('--сломать');

const ПРОВЕРКИ = [];
function проверить(имя, условие, подробности) {
  ПРОВЕРКИ.push({ имя: имя, ошибка: условие ? null : (подробности || 'условие не выполнено') });
}

/** Своя копия server/ во временной папке — боевой код и данные не трогаем. */
function подготовитьКопиюСервера() {
  const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'срочная-запись-силы-'));
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(врем, 'server'), { recursive: true });
  return path.join(врем, 'server', 'сила-игроков.js');
}

/**
 * Порча копии: возвращает записатьСрочно() обратно к пятисекундному
 * отложенному письму (тот же .unref(), что был раньше у записатьПогодя) —
 * ровно регрессия, о которой предупреждал штаб.
 */
function испортитьКопию(путьКСиле) {
  const исходник = fs.readFileSync(путьКСиле, 'utf8');
  const было = 'function записатьСрочно() {\n' +
    '  if (!записьРазрешена) return;\n' +
    '  естьЧтоЗаписать = true;\n' +
    '  записатьСейчас();\n' +
    '}';
  if (исходник.indexOf(было) === -1) {
    throw new Error('не нашёл тело записатьСрочно() для порчи — код server/сила-игроков.js изменился, поправьте tests/срочная-запись-силы.js');
  }
  const испорчено = исходник.replace(было,
    'function записатьСрочно() {\n' +
    '  if (!записьРазрешена) return;\n' +
    '  естьЧтоЗаписать = true;\n' +
    '  /* ИСПОРЧЕНО ПРОВЕРКОЙ tests/срочная-запись-силы.js --сломать: снова ждём 5 секунд */\n' +
    '  var т = setTimeout(function () { записатьСейчас(); }, 5000);\n' +
    '  if (т.unref) т.unref();\n' +
    '}');
  fs.writeFileSync(путьКСиле, испорчено, 'utf8');
}

/**
 * Раннер: в отдельном процессе засчитывает одну партию и СРАЗУ
 * завершается через process.exit(0), без дописать() — модель «сервер
 * упал в первую же миллисекунду после конца партии».
 */
function кодРаннера(папкаДанных, путьКСиле, застольем) {
  return [
    "process.env.GAMES_DATA = " + JSON.stringify(папкаДанных) + ";",
    "const сила = require(" + JSON.stringify(путьКСиле) + ");",
    "сила.включитьЗапись();",
    "сила.учесть('дурак', " + JSON.stringify(застольем) + ");",
    "process.exit(0);"
  ].join('\n');
}

/** Засчитать партию в отдельном процессе и вернуть, что осталось на диске. */
function засчитатьВОтдельномПроцессе(путьКСиле, застольем) {
  const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'срочная-запись-силы-раннер-'));
  const папкаДанных = path.join(врем, 'данные');
  const файлРаннера = path.join(врем, 'раннер.js');
  fs.writeFileSync(файлРаннера, кодРаннера(папкаДанных, путьКСиле, застольем), 'utf8');

  execFileSync(process.execPath, [файлРаннера], { stdio: 'pipe' });

  const файлСилы = path.join(папкаДанных, 'сила.json');
  if (!fs.existsSync(файлСилы)) return null;
  return JSON.parse(fs.readFileSync(файлСилы, 'utf8'));
}

/** Запись игрока в прочитанном файле силы (или null). */
function записьИгрока(данные, номер) {
  if (!данные || !Array.isArray(данные.игроки)) return null;
  return данные.игроки.find(function (з) { return з.номер === номер; }) || null;
}

/* -----------------------------------------------------------------------
   main
   ----------------------------------------------------------------------- */

const путьКСиле = подготовитьКопиюСервера();
if (СЛОМАТЬ) испортитьКопию(путьКСиле);

const победитель = { номер: 1001, имя: 'Аня', этоБот: false, победил: true };
const проигравший = { номер: 1002, имя: 'Боря', этоБот: false, победил: false };
const данные = засчитатьВОтдельномПроцессе(путьКСиле, [победитель, проигравший]);
const записьПобедителя = записьИгрока(данные, 1001);
const записьПроигравшего = записьИгрока(данные, 1002);

проверить(
  'сила победителя есть на диске сразу после «падения» процесса',
  !!записьПобедителя && записьПобедителя.партий === 1 && записьПобедителя.сила > 1500,
  данные === null
    ? 'файл силы вообще не появился — сила потерялась, как предупреждал штаб'
    : 'запись игрока 1001: ' + JSON.stringify(записьПобедителя) + ' (ждали партий=1 и силу больше 1500)'
);

проверить(
  'сила проигравшего есть на диске сразу после «падения» процесса',
  !!записьПроигравшего && записьПроигравшего.партий === 1 && записьПроигравшего.сила < 1500,
  данные === null
    ? 'файл силы вообще не появился — сила потерялась, как предупреждал штаб'
    : 'запись игрока 1002: ' + JSON.stringify(записьПроигравшего) + ' (ждали партий=1 и силу меньше 1500)'
);

console.log('');
let провалов = 0;
for (const п of ПРОВЕРКИ) {
  if (п.ошибка) {
    провалов++;
    console.log('  ПРОВАЛ ' + п.имя + ': ' + п.ошибка);
  } else {
    console.log('  ок     ' + п.имя);
  }
}
console.log('');
console.log('Итого проверок: ' + ПРОВЕРКИ.length + ', провалов: ' + провалов);
process.exit(провалов > 0 ? 1 : 0);
