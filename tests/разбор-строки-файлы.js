// Функция подходит() не экспортируется — вырезаем её текст (и нормализовать(),
// от которой она зависит) из настоящего файла и собираем в песочнице vm.
// Файл при этом не читается как модуль целиком (не выполняется его побочный
// ход с чтением stdin и process.exit) и не правится.
function извлечьФункцииОхраны(текстОхраны) {
  function вырезать(имя) {
    const начало = текстОхраны.indexOf('function ' + имя + '(');
    if (начало === -1) throw new Error('в охране не нашлась функция ' + имя);
    const индексСкобки = текстОхраны.indexOf('{', начало);
    let глубина = 0;
    let конец = -1;
    for (let i = индексСкобки; i < текстОхраны.length; i++) {
      if (текстОхраны[i] === '{') глубина++;
      else if (текстОхраны[i] === '}') {
        глубина--;
        if (глубина === 0) { конец = i + 1; break; }
      }
    }
    if (конец === -1) throw new Error('не нашлась закрывающая скобка функции ' + имя);
    return текстОхраны.slice(начало, конец);
  }

  const исходник = 'const path = require("path");\n'
    + 'const КОРЕНЬ = ' + JSON.stringify(КОРЕНЬ) + ';\n'
    + вырезать('нормализовать') + '\n'
    + вырезать('подходит') + '\n'
    + 'module.exports = { нормализовать: нормализовать, подходит: подходит };\n';

  const песочница = { module: { exports: {} }, require: require };
  vm.createContext(песочница);
  vm.runInContext(исходник, песочница, { filename: 'охрана-извлечённое.js' });
  return песочница.module.exports;
}

const текстОхраны = fs.readFileSync(ФАЙЛ_ХУКА_ОХРАНА, 'utf8');
const { подходит } = извлечьФункцииОхраны(текстОхраны);

