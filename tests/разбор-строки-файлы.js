function равны(получено, ожидается) {
  return JSON.stringify(получено) === JSON.stringify(ожидается);
}

// ---------- путиИзСтроки(): настоящий хук либо одна из его порченых копий ----------
// Замены — список пар {метка, замена}: сеть защит теперь двухслойная (первая
// проверка в цикле разбора + независимая маскаБезопасна() после сборки), для
// одной и той же дыры иногда нужно вырезать оба слоя разом — иначе оставшийся
// слой молча компенсирует испорченный, и ломающий прогон не краснеет.
function загрузитьХукПортя(замены, названиеРежима) {
  const текстОригинал = fs.readFileSync(ФАЙЛ_ХУКА_НАЧАЛО, 'utf8');
  let текстСломанный = текстОригинал;
  const ненайденные = [];
  for (const { метка, замена } of замены) {
    if (!текстСломанный.includes(метка)) {
      ненайденные.push(метка);
      continue;
    }
    текстСломанный = текстСломанный.replace(метка, замена);
  }

  проверить(
    '0. порча копии начало-исполнителя.js применилась (' + названиеРежима + ') — иначе текст хука изменился, и проверку надо обновить',
    ненайденные.length === 0,
    ненайденные.length ? 'не найдены строки: ' + JSON.stringify(ненайденные) : ''
  );

  const времПапка = fs.mkdtempSync(path.join(os.tmpdir(), 'разбор-строки-файлы-'));
  const времФайл = path.join(времПапка, 'начало-исполнителя.js');
  fs.writeFileSync(времФайл, текстСломанный, 'utf8');
  return require(времФайл).путиИзСтроки;
}

