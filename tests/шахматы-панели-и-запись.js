const спать = (мс) => new Promise((ф) => setTimeout(ф, мс));

async function новаяСтраница(браузер, ш, в) {
  const окно = await браузер.newContext({ viewport: { width: ш, height: в }, hasTouch: true, deviceScaleFactor: 2 });
  const страница = await окно.newPage();
  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
    красные.push('консоль: ' + м.text());
  });
  await подготовитьПодделку(страница, { версия: '8.0', полныйЭкран: 'дают' });
  await страница.goto(АДРЕС);
  await спать(600);
  return { окно, страница, красные };
}

/** Тап по клетке доски по её имени поля («e2», «d5»…). */
async function тап(страница, поле) {
  await страница.evaluate((имя) => {
    const клетка = document.querySelector('[data-поле="' + имя + '"]');
    if (клетка) клетка.click();
  }, поле);
}

/** Сделать ход двумя касаниями — откуда и куда. */
async function сходить(страница, откуда, куда) {
  await тап(страница, откуда);
  await спать(120);
  await тап(страница, куда);
  await спать(150);
}

/**
 * Прочитать ленту #запись-ходов так, как её читает глаз: с пробелом
 * между каждым узлом (номер/ход/ход). Простой textContent контейнера
 * склеивает узлы без пробелов («1.e4d5») — CSS-отступы (gap) в него
 * не попадают, это не то, что видит человек.
 */
async function текстЛенты(страница) {
  return страница.evaluate(() => {
    const лента = document.getElementById('запись-ходов');
    if (!лента) return null;
    const части = [];
    for (const пара of лента.querySelectorAll('.запись-ходов__пара')) {
      for (const узел of пара.children) части.push((узел.textContent || '').trim());
    }
    return { текст: части.join(' '), пустаяЛента: лента.textContent === '', детейВЛенте: лента.children.length };
  });
}

/** Снимок панелей и трофеев — по значку цвета, не по id верх/низ (см. шапку файла). */
async function снимокПанелей(страница) {
  return страница.evaluate(() => {
    function панель(суффикс) {
      const узел = document.getElementById('панель-' + суффикс);
      const имя = document.getElementById('имя-' + суффикс);
      const цвет = document.getElementById('цвет-' + суффикс);
      const трофеи = document.getElementById('трофеи-' + суффикс);
      const белый = цвет ? цвет.classList.contains('фигура--белая') : null;
      return {
        есть: !!узел,
        имя: имя ? имя.textContent.trim() : '',
        цветБелый: белый,
        трофеевУзлов: трофеи ? трофеи.querySelectorAll('.фигура').length : -1,
        трофеиКлассы: трофеи ? [...трофеи.querySelectorAll('.фигура')].map((ф) => ф.className) : [],
        перевес: трофеи ? (трофеи.querySelector('.панель-игрока-шахмат__перевес') || {}).textContent || '' : ''
      };
    }
    const сверху = панель('сверху');
    const снизу = панель('снизу');
    // Панель, где сейчас стоит значок БЕЛОГО цвета — «панель белых».
    const белая = сверху.цветБелый ? сверху : (снизу.цветБелый ? снизу : null);
    const чёрная = сверху.цветБелый ? снизу : (снизу.цветБелый ? сверху : null);
    return { сверху, снизу, белая, чёрная };
  });
}

/** Кто физически стоит сверху на доске: смотрим ряд первой (по top) строки клеток. */
async function физическийВерхДоски(страница) {
  return страница.evaluate(() => {
    const клетки = [...document.querySelectorAll('#доска .поле')];
    if (!клетки.length) return null;
    let минTop = Infinity;
    for (const к of клетки) минTop = Math.min(минTop, к.getBoundingClientRect().top);
    const верхние = клетки.filter((к) => Math.abs(к.getBoundingClientRect().top - минTop) < 1);
    const ряды = new Set(верхние.map((к) => Number((к.getAttribute('data-поле') || '').replace(/\D/g, ''))));
    // Стандартная расстановка: ряд 8 — чёрные начинают там, ряд 1 — белые.
    if (ряды.has(8) && !ряды.has(1)) return 'чёрные';
    if (ряды.has(1) && !ряды.has(8)) return 'белые';
    return 'непонятно: ' + [...ряды].join(',');
  });
}

