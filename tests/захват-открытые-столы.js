const fs = require('fs');
const os = require('os');
const path = require('path');
const { поднять, сделатьДокумент } = require('./поддельный-браузер.js');

const КОРЕНЬ = path.join(__dirname, '..');
const ИГРА = 'захват';
/* Порог: меньше проверок на чистом прогоне — значит, часть молча не сработала. */
const МИНИМУМ_ПРОВЕРОК = 16;

function довод(имя) {
  const найден = process.argv.find(function (д) { return д.indexOf('--' + имя + '=') === 0; });
  return найден ? найден.slice(имя.length + 3) : '';
}

const СЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;

function подождать() {
  return new Promise(function (готово) { setTimeout(готово, 0); });
}

/** Найти объявление списка «const ИМЯ = [ ... ];» ровно один раз и вернуть
    его слова. Не нашли или нашли не одно — ошибка (ноль найденного = провал). */
function найтиСписок(исходник, имя) {
  const регулярка = new RegExp('const ' + имя + ' = \\[([^\\]]*)\\];', 'g');
  const найдено = исходник.match(регулярка);
  if (!найдено || найдено.length !== 1) {
    throw new Error('объявление «const ' + имя + ' = [...]» найдено ' +
      (найдено ? найдено.length : 0) + ' раз(а), нужно ровно один');
  }
  const слова = найдено[0].match(/'([^']+)'/g) || [];
  return слова.map(function (с) { return с.slice(1, -1); });
}

/* ---------------------------------------------------------------------
   Сами проверки. Возвращают список {ок, текст}, ничего не печатают и не
   завершают процесс — так их можно прогнать и на живых файлах, и на порченых копиях.
   --------------------------------------------------------------------- */

async function построитьЭкранСтолов(исходникСтолов, играСтраницы) {
  const документ = сделатьДокумент();
  const рез = поднять(исходникСтолов, {
    документ: документ,
    fetch: function () { return new Promise(function () {}); },
    имяФайла: 'js/открытые-столы.js'
  });
  рез.окно.ИграСтраницы = играСтраницы;
  if (!рез.окно.ЭкранОткрытыхСтолов || typeof рез.окно.ЭкранОткрытыхСтолов.открыть !== 'function') {
    throw new Error('window.ЭкранОткрытыхСтолов.открыть не появилась');
  }
  рез.окно.ЭкранОткрытыхСтолов.открыть();
  await подождать();
  return документ;
}

async function проверитьСтолы(путьСтолов) {
  const итог = [];
  const ок = function (условие, текст) { итог.push({ ок: Boolean(условие), текст: текст }); };
  const исходник = fs.readFileSync(путьСтолов, 'utf8');

  try {
    const список = найтиСписок(исходник, 'ИГРЫ_С_ПОДБОРОМ');
    ок(список.indexOf(ИГРА) !== -1, 'открытые-столы: «' + ИГРА + '» есть в ИГРЫ_С_ПОДБОРОМ');
    ок(список.indexOf('шашки') !== -1, 'открытые-столы: старые игры на месте (в списке есть «шашки»)');
  } catch (сбой) {
    ок(false, 'открытые-столы: ' + сбой.message);
  }

  try {
    const idКнопки = (исходник.match(/const КНОПКА_ПОДБОР = '([^']+)';/) || [])[1];
    ок(idКнопки, 'открытые-столы: id кнопки «Найти игру» найден в исходнике');
    const документ = await построитьЭкранСтолов(исходник, ИГРА);
    ок(документ.getElementById('экран-открытые-столы'), 'открытые-столы: экран «Играть онлайн» построился на странице «' + ИГРА + '»');
    ок(idКнопки && документ.getElementById(idКнопки), 'открытые-столы: на странице «' + ИГРА + '» кнопка «Найти игру» видна');
    const чужая = await построитьЭкранСтолов(исходник, 'игра-которой-нет');
    ок(idКнопки && !чужая.getElementById(idКнопки), 'открытые-столы: на странице чужой игры кнопки «Найти игру» нет (список не «открыт всем»)');
  } catch (сбой) {
    ок(false, 'открытые-столы: упало — ' + (сбой && сбой.message || сбой));
  }
  return итог;
}

/** Вид комнаты, как его шлёт сервер (образец — tests/комната-подпись-игры.js). */
function видКомнаты(добавки) {
  return Object.assign({
    игра: ИГРА, этап: 'ожидание', мест: 2, мойНомер: 1, яХозяин: true,
    можноНачать: false, переводной: false, парами: false, открытыйСтол: true,
    застолом: [{ номер: 1, этоЯ: true, имя: 'Аня', хозяин: true, наСвязи: true }]
  }, добавки || {});
}

/** Сверка с сервером (только чтение): в столГодитсяИскателю условие «стол ровно
    на двоих» стоит только у дурака. Вернуть игры, у которых такое условие есть.
    Тело функции или условие не найдено — ошибка (ноль найденного = провал). */
function игрыСДвоимиНаСервере(исходникСервера) {
  const начало = исходникСервера.indexOf('function столГодитсяИскателю(');
  if (начало === -1) throw new Error('сервер: функция столГодитсяИскателю не найдена');
  /* Файл может быть с переводами строк Windows (\r\n) — ищем закрывающую скобку на своей строке. */
  const закрытие = /\r?\n\}\r?\n/g;
  закрытие.lastIndex = начало;
  const найденоЗакрытие = закрытие.exec(исходникСервера);
  const конец = найденоЗакрытие ? найденоЗакрытие.index : -1;
  if (конец === -1) throw new Error('сервер: конец функции столГодитсяИскателю не найден');
  const тело = исходникСервера.slice(начало, конец);
  const условия = тело.match(/игра === '[^']+'/g) || [];
  /* Первая строка тела — «играСтола(комната) !== игра»: она с «!==» и сюда не попадает. */
  if (условия.length !== 1) {
    throw new Error('сервер: в столГодитсяИскателю условий «игра === \'…\'» найдено ' + условия.length + ', нужно ровно одно');
  }
  return условия.map(function (у) { return у.match(/'([^']+)'/)[1]; });
}

function проверитьСервер(путьСервера) {
  const итог = [];
  const ок = function (условие, текст) { итог.push({ ок: Boolean(условие), текст: текст }); };
  try {
    const игры = игрыСДвоимиНаСервере(fs.readFileSync(путьСервера, 'utf8'));
    ок(игры.length === 1 && игры[0] === 'дурак', 'сервер: «стол ровно на двоих» в столГодитсяИскателю стоит только у дурака (найдено: ' + игры.join(', ') + ')');
    ок(игры.indexOf(ИГРА) === -1, 'сервер: у «' + ИГРА + '» ограничения «на двоих» нет — подбор сажает за стол любого размера');
  } catch (сбой) {
    ок(false, сбой.message);
  }
  return итог;
}

function проверитьКомнату(путьКомнаты, игрыСервера) {
  const итог = [];
  const ок = function (условие, текст) { итог.push({ ок: Boolean(условие), текст: текст }); };
  const исходник = fs.readFileSync(путьКомнаты, 'utf8');

  let всеИгры = [];
  let наДвоих = [];
  try {
    всеИгры = найтиСписок(исходник, 'ИГРЫ_С_ПОДБОРОМ');
    наДвоих = найтиСписок(исходник, 'ИГРЫ_С_ПОДБОРОМ_ТОЛЬКО_НА_ДВОИХ');
  } catch (сбой) {
    ок(false, 'комната: ' + сбой.message);
    return итог;
  }
  ок(всеИгры.indexOf(ИГРА) !== -1, 'комната: «' + ИГРА + '» есть в ИГРЫ_С_ПОДБОРОМ');
  ок(наДвоих.indexOf(ИГРА) === -1, 'комната: «' + ИГРА + '» НЕТ в ИГРЫ_С_ПОДБОРОМ_ТОЛЬКО_НА_ДВОИХ (сервер не требует стола на двоих)');
  ок(всеИгры.indexOf('дурак') !== -1 && наДвоих.indexOf('дурак') !== -1, 'комната: «дурак» в обоих списках на месте');
  ок(наДвоих.slice().sort().join(',') === игрыСервера.slice().sort().join(','),
    'комната: список «только на двоих» совпадает с сервером (клиент: ' + наДвоих.join(', ') + '; сервер: ' + игрыСервера.join(', ') + ')');

  try {
    const ДуракКомната = require(путьКомнаты);
    const собрать = ДуракКомната.создать({}).собрать;
    const СЛОВА = ДуракКомната.СЛОВА;
    const на2 = собрать(видКомнаты({ мест: 2 })).подбор;
    ок(на2 && на2.видна === true, 'комната: у стола «' + ИГРА + '» переключатель подбора виден');
    ок(на2 && на2.включён === true, 'комната: у открытого стола «' + ИГРА + '» подбор включён');
    ок(на2 && на2.доступен === true, 'комната: хозяин может переключить подбор у «' + ИГРА + '»');
    ок(на2 && на2.пометка === '', 'комната: стол «' + ИГРА + '» на двоих — пометки «только на двоих» нет');
    const на4 = собрать(видКомнаты({ мест: 4 })).подбор;
    ок(на4 && на4.видна === true && на4.включён === true,
      'комната: стол «' + ИГРА + '» на четверых — переключатель подбора виден и включён');
    ок(СЛОВА && СЛОВА.подборТолькоНаДвоих && на4 && на4.пометка === '',
      'комната: стол «' + ИГРА + '» на четверых — пометки «только на двоих» НЕТ (она бы соврала)');
    const дурак4 = собрать(видКомнаты({ игра: 'дурак', мест: 4 })).подбор;
    ок(дурак4 && дурак4.пометка === СЛОВА.подборТолькоНаДвоих,
      'комната: у дурака на четверых пометка «только на двоих» по-прежнему есть (проверка умеет её видеть)');
  } catch (сбой) {
    ок(false, 'комната: упало — ' + (сбой && сбой.stack || сбой));
  }
  return итог;
}

