/** Убрать «захват» из одного списка в копии; место порчи — ровно одно. */
function испортитьСписок(исходник, имяСписка) {
  const регулярка = new RegExp('(const ' + имяСписка + ' = \\[[^\\]]*?),\\s*\'' + ИГРА + '\'([^\\]]*\\];)', 'g');
  const найдено = исходник.match(регулярка) || [];
  if (найдено.length !== 1) {
    throw new Error('место порчи «' + имяСписка + '» найдено ' + найдено.length + ' раз(а), нужно ровно одно');
  }
  return исходник.replace(регулярка, '$1$2');
}

/** Добавить «захват» в список в копии (порча «лишний захват»); место — ровно одно. */
function добавитьВСписок(исходник, имяСписка) {
  const регулярка = new RegExp('(const ' + имяСписка + ' = \\[[^\\]]*?)(\\];)', 'g');
  const найдено = исходник.match(регулярка) || [];
  if (найдено.length !== 1) {
    throw new Error('место порчи «' + имяСписка + '» найдено ' + найдено.length + ' раз(а), нужно ровно одно');
  }
  return исходник.replace(регулярка, '$1, \'' + ИГРА + '\'$2');
}

/** Серверу «захват» приписано условие «стол на двоих» — как будто его ввели только там. */
function испортитьСервер(исходник) {
  const было = /if \(игра === 'дурак'\) \{(\r?\n\s*if \(комната\.мест !== 2)/g;
  const места = (исходник.match(было) || []).length;
  if (места !== 1) throw new Error('место порчи сервера найдено ' + места + ' раз(а), нужно ровно одно');
  return исходник.replace(было, "if (игра === 'дурак' || игра === '" + ИГРА + "') {$1");
}

async function сломатьИПроверить() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-открытые-столы-сломать-'));
  let поломок = 0;
  let покраснело = 0;
  const живыеСтолы = path.join(КОРЕНЬ, 'js', 'открытые-столы.js');
  const живаяКомната = path.join(КОРЕНЬ, 'js', 'дурак-комната.js');
  const живойСервер = path.join(КОРЕНЬ, 'server', 'комнаты.js');
  const порчи = [
    { имя: 'открытые-столы: «захват» убран из ИГРЫ_С_ПОДБОРОМ', файл: 'столы', портить: function (т) { return испортитьСписок(т, 'ИГРЫ_С_ПОДБОРОМ'); } },
    { имя: 'комната: «захват» убран из ИГРЫ_С_ПОДБОРОМ', файл: 'комната', портить: function (т) { return испортитьСписок(т, 'ИГРЫ_С_ПОДБОРОМ'); } },
    { имя: 'комната: «захват» добавлен в ИГРЫ_С_ПОДБОРОМ_ТОЛЬКО_НА_ДВОИХ', файл: 'комната', портить: function (т) { return добавитьВСписок(т, 'ИГРЫ_С_ПОДБОРОМ_ТОЛЬКО_НА_ДВОИХ'); } },
    { имя: 'сервер: «захват» получил условие «стол на двоих»', файл: 'сервер', портить: испортитьСервер }
  ];
  try {
    for (let номер = 0; номер < порчи.length; номер++) {
      const порча = порчи[номер];
      поломок++;
      const живой = { столы: живыеСтолы, комната: живаяКомната, сервер: живойСервер }[порча.файл];
      let копия;
      try {
        копия = path.join(папка, 'порча-' + (номер + 1) + '-' + path.basename(живой));
        fs.writeFileSync(копия, порча.портить(fs.readFileSync(живой, 'utf8')), 'utf8');
      } catch (сбой) {
        console.log('  ПРОВАЛ порчи — ' + порча.имя + ': ' + сбой.message);
        continue;
      }
      /* Комнату сверяем с НАСТОЯЩИМ сервером, серверную порчу — сама сверка с сервером. */
      let результат;
      if (порча.файл === 'столы') результат = await проверитьСтолы(копия);
      else if (порча.файл === 'комната') результат = проверитьКомнату(копия, игрыСДвоимиНаСервере(fs.readFileSync(живойСервер, 'utf8')));
      else результат = проверитьСервер(копия);
      const красные = результат.filter(function (р) { return !р.ок; });
      if (красные.length > 0) {
        покраснело++;
        console.log('  покраснело — ' + порча.имя + ' (красных проверок: ' + красные.length + ')');
      } else {
        console.log('  НЕ ПОКРАСНЕЛО — ' + порча.имя);
      }
    }
  } finally {
    try { fs.rmSync(папка, { recursive: true, force: true }); } catch (сбой) { /* не страшно */ }
  }
  console.log('\nПоломок: ' + поломок + ', покраснело: ' + покраснело);
  process.exit(поломок > 0 && поломок === покраснело ? 0 : 1);
}

async function главное() {
  if (СЛОМАТЬ) {
    console.log('*** ЛОМАЮЩИЙ ЗАПУСК: копии с убранным «' + ИГРА + '» во временной папке — каждая порча обязана покраснеть ***');
    await сломатьИПроверить();
    return;
  }
  const путьСтолов = довод('столы') || path.join(КОРЕНЬ, 'js', 'открытые-столы.js');
  const путьКомнаты = довод('комната') || path.join(КОРЕНЬ, 'js', 'дурак-комната.js');
  const путьСервера = довод('сервер') || path.join(КОРЕНЬ, 'server', 'комнаты.js');
  let игрыСервера = [];
  try { игрыСервера = игрыСДвоимиНаСервере(fs.readFileSync(путьСервера, 'utf8')); } catch (сбой) { /* провал покажет проверитьСервер */ }
  const все = (await проверитьСтолы(путьСтолов)).concat(проверитьКомнату(путьКомнаты, игрыСервера), проверитьСервер(путьСервера));
  for (const п of все) console.log((п.ок ? '  ок    — ' : '  ПЛОХО — ') + п.текст);
  const провалы = все.filter(function (п) { return !п.ок; }).length;
  const мало = все.length < МИНИМУМ_ПРОВЕРОК;
  if (мало) console.log('  ПЛОХО — проверок слишком мало: ' + все.length + ' < ' + МИНИМУМ_ПРОВЕРОК);
  console.log('\nИтого проверок: ' + все.length + ', провалов: ' + провалы);
  process.exit(провалы || мало ? 1 : 0);
}

главное().catch(function (сбой) {
  console.error('Проверка упала: ' + (сбой && сбой.stack || сбой));
  process.exit(2);
});
