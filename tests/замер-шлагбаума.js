/* ---------------------------------------------------------------------
   Замер 5б. Настоящий сетевой автопрогон на разном числе комнат.
   Для каждого числа поднимаем ЧИСТЫЙ сервер отдельной программой —
   иначе неудачи прошлого прогона портят следующий.
   --------------------------------------------------------------------- */

/** Поднять сервер комнат отдельной программой и дождаться, пока он живой. */
function поднятьОтдельныйСервер(порт) {
  return new Promise(function (готово, беда) {
    const дитя = spawn(process.execPath,
      [path.join(__dirname, '..', 'server', 'сервер.js'), String(порт)],
      { stdio: ['ignore', 'pipe', 'pipe'] });

    let сдался = false;
    дитя.stderr.on('data', function (кусок) {
      if (!сдался) { сдался = true; беда(new Error('сервер не запустился: ' + кусок.toString().trim())); }
    });
    дитя.stdout.on('data', function (кусок) {
      if (!сдался && /работает на порту/.test(кусок.toString())) { сдался = true; готово(дитя); }
    });
    setTimeout(function () {
      if (!сдался) { сдался = true; беда(new Error('сервер не отозвался за 10 секунд')); }
    }, 10000);
  });
}

/** Прогнать настоящий tests/сетевой-автопрогон.js и вернуть, чем кончилось. */
function прогнать(порт, комнат) {
  return new Promise(function (готово) {
    const начало = Date.now();
    const дитя = spawn(process.execPath,
      [path.join(__dirname, 'сетевой-автопрогон.js'), String(порт), String(комнат)],
      { stdio: ['ignore', 'pipe', 'pipe'] });

    let весьВывод = '';
    дитя.stdout.on('data', function (к) { весьВывод += к.toString(); });
    дитя.stderr.on('data', function (к) { весьВывод += к.toString(); });
    дитя.on('close', function (код) {
      готово({ код: код, мс: Date.now() - начало, вывод: весьВывод });
    });
  });
}

