'use strict';

/* =====================================================================
   Злые запросы к серверу комнат.

   Здесь мы нарочно ведём себя как испорченный клиент или как чужой
   человек, который хочет влезть в чужую игру: шлём мусор вместо чисел,
   отрицательные номера карт, чужие пропуски, огромные тела запросов,
   перебираем коды комнат.

   Сервер после всего этого обязан:
     — остаться живым;
     — не пустить чужого в чужую партию;
     — ни разу не показать чужие карты;
     — на любую дичь ответить понятным отказом, а не молчанием.

   Запуск (сервер комнат должен быть уже поднят):
       node tests/злые-запросы-к-серверу.js 8790
   ===================================================================== */

const http = require('http');

const ПОРТ = Number(process.argv[2]) || 8765;
const ХОСТ = '127.0.0.1';

const провалы = [];
let проверок = 0;

function проверить(условие, что, подробность) {
  проверок++;
  if (!условие) провалы.push(что + (подробность ? ' — ' + подробность : ''));
}

function запрос(путь, тело, способ) {
  return new Promise(function (готово, беда) {
    const текст = typeof тело === 'string' ? Buffer.from(тело, 'utf8')
                                           : Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const о = http.request({
      host: ХОСТ, port: ПОРТ, method: способ || 'POST', path: encodeURI(путь),
      headers: { 'Content-Type': 'application/json', 'Content-Length': текст.length }
    }, function (ответ) {
      let к = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (ч) { к += ч; });
      ответ.on('end', function () {
        let данные = null;
        try { данные = JSON.parse(к); } catch (сбой) { данные = { сыройОтвет: к }; }
        готово({ номер: ответ.statusCode, данные: данные, сырой: к });
      });
    });
    о.setTimeout(15000, function () { о.destroy(new Error('нет ответа на ' + путь)); });
    о.on('error', беда);
    о.end(текст);
  });
}

function здоровье() {
  return new Promise(function (готово, беда) {
    http.get({ host: ХОСТ, port: ПОРТ, path: encodeURI('/здоровье') }, function (ответ) {
      let к = '';
      ответ.on('data', function (ч) { к += ч; });
      ответ.on('end', function () {
        try { готово(JSON.parse(к)); } catch (с) { беда(new Error('не JSON')); }
      });
    }).on('error', беда);
  });
}

/** Есть ли в ответе хоть одна карта. Нужен, чтобы ловить утечку чужой руки. */
function естьКарты(что) {
  let нашли = false;
  (function обход(узел) {
    if (нашли || !узел || typeof узел !== 'object') return;
    if (узел.масть !== undefined && узел.имя !== undefined) { нашли = true; return; }
    Object.keys(узел).forEach(function (к) { обход(узел[к]); });
  })(что);
  return нашли;
}

async function главное() {
  console.log('=== Злые запросы к серверу комнат ===');
  console.log('сервер: http://' + ХОСТ + ':' + ПОРТ);

  try { await здоровье(); } catch (сбой) {
    console.error('Сервер не отвечает. Запустите: node server/сервер.js ' + ПОРТ);
    process.exit(1);
  }

  /* ---- 1. Мусор вместо честного запроса ---- */
  const мусор = [
    ['не JSON вовсе', '/создать', 'это не json {{{'],
    ['пустое тело', '/войти', ''],
    ['вместо объекта — число', '/войти', '12345'],
    ['вместо объекта — строка', '/войти', '"привет"'],
    ['вместо объекта — список', '/ход', '[1,2,3]'],
    ['очень длинное тело', '/войти', JSON.stringify({ код: 'A'.repeat(50000) })]
  ];
  for (const [подпись, путь, тело] of мусор) {
    const о = await запрос(путь, тело);
    проверить(о.номер >= 400 && о.номер < 500,
      'мусор «' + подпись + '»: сервер ответил не отказом', 'код ' + о.номер);
    проверить(!естьКарты(о.данные), 'мусор «' + подпись + '»: в отказе оказались карты');
  }

  /* ---- 2. Несуществующие адреса и чужие способы обращения ---- */
  const нетТакого = await запрос('/такого-адреса-нет', {});
  проверить(нетТакого.номер === 404, 'несуществующий адрес не дал 404', 'код ' + нетТакого.номер);
  const неТотСпособ = await запрос('/создать', {}, 'PUT');
  проверить(неТотСпособ.номер === 405, 'запрос способом PUT не отклонён', 'код ' + неТотСпособ.номер);

  /* ---- 3. Чужие и кривые пропуска ---- */
  const комната = await запрос('/создать', {});
  const код = комната.данные.код;
  const пропуск1 = комната.данные.пропуск;
  проверить(typeof код === 'string' && /^[A-Z0-9]{4}$/.test(код), 'код комнаты не из четырёх знаков', код);
  проверить(typeof пропуск1 === 'string' && пропуск1.length >= 24, 'пропуск слишком короткий');

  const кривыеПропуска = [null, '', 0, 123, true, [], {}, 'ffffffffffffffffffffffffffffffff', пропуск1 + 'x'];
  for (const п of кривыеПропуска) {
    const о = await запрос('/состояние', { код: код, пропуск: п });
    проверить(о.номер === 404, 'чужой пропуск ' + JSON.stringify(п) + ' пустили в комнату', 'код ' + о.номер);
    проверить(!естьКарты(о.данные), 'чужому пропуску ' + JSON.stringify(п) + ' показали карты');
  }

  /* ---- 4. Перебор кодов: сколько попыток сервер съедает за секунду ---- */
  const началоПеребора = Date.now();
  let попыток = 0;
  let угадали = 0;
  while (Date.now() - началоПеребора < 1000) {
    const о = await запрос('/войти', { код: 'ZZ' + String(попыток % 100).padStart(2, '0') });
    попыток++;
    if (о.номер === 200) угадали++;
  }
  const скорость = попыток;
  console.log('перебор кодов: сервер принял ' + скорость + ' попыток входа за секунду подряд' +
              (угадали ? ', угадано комнат: ' + угадали : ''));

  /* ---- 5. Дичь в самом ходе ---- */
  const вход = await запрос('/войти', { код: код });
  проверить(вход.номер === 200, 'друг не смог войти в свежую комнату');
  const пропуск2 = вход.данные.пропуск;

  /* Про «карта: null» и «карта: "0"» отдельно. Сервер приводит их к нулю
     и играет первой картой из руки. Жульничества здесь нет — своей первой
     картой игрок и так имеет право сходить, — поэтому в список дурных
     ходов их не кладём, но вслух об этом говорим ниже. */
  const дурныеХоды = [
    { действие: 'ходить', карта: -1 },
    { действие: 'ходить', карта: 999999 },
    { действие: 'ходить', карта: 'первая' },
    { действие: 'ходить', карта: 1.5 },
    { действие: 'отбить', пара: -5, карта: -5 },
    { действие: 'отбить', пара: 1e9, карта: 1e9 },
    { действие: 'взорвать-стол' },
    { действие: '' },
    { действие: 42 },
    {}
  ];
  // Пробуем от имени обоих: кто-то из них сейчас ходит, и это важнее всего
  for (const пропуск of [пропуск1, пропуск2]) {
    for (const намерение of дурныеХоды) {
      const о = await запрос('/ход', Object.assign({ код: код, пропуск: пропуск }, намерение));
      проверить(о.номер === 200, 'дурной ход уронил сервер в ошибку', JSON.stringify(намерение) + ' → ' + о.номер);
      проверить(о.данные && о.данные.принято === false,
        'сервер принял дурной ход', JSON.stringify(намерение));
      проверить(typeof (о.данные && о.данные.причина) === 'string' && о.данные.причина.length > 5,
        'отказ без человеческого объяснения', JSON.stringify(намерение) + ' → ' + JSON.stringify(о.данные && о.данные.причина));
    }
  }

  /* Отдельно смотрим, что делает сервер с «пустым» номером карты. Сходить
     чужой картой так нельзя — можно только своей первой, поэтому это
     не дыра, а мягкость разбора. Пишем словами, чтобы никто не пугался. */
  const пустойНомер = await запрос('/ход', { код: код, пропуск: пропуск1, действие: 'ходить', карта: null });
  const пустойНомер2 = await запрос('/ход', { код: код, пропуск: пропуск2, действие: 'ходить', карта: null });
  const принялПустой = (пустойНомер.данные && пустойНомер.данные.принято) ||
                       (пустойНомер2.данные && пустойНомер2.данные.принято);
  console.log('пустой номер карты (карта: null): сервер ' +
              (принялПустой ? 'считает его нулём и играет первой картой из своей руки' : 'отказывает'));

  /* ---- 6. Чужой пытается подсмотреть партию через длинный опрос ---- */
  const подсмотр = await запрос('/что-нового', { код: код, пропуск: 'a'.repeat(32), версия: 0 });
  проверить(подсмотр.номер === 404, 'чужого пустили на длинный опрос', 'код ' + подсмотр.номер);
  проверить(!естьКарты(подсмотр.данные), 'чужому показали карты в длинном опросе');

  /* ---- 7. Выход два раза подряд и ходы после выхода ---- */
  await запрос('/выйти', { код: код, пропуск: пропуск1 });
  const второйВыход = await запрос('/выйти', { код: код, пропуск: пропуск1 });
  проверить(второйВыход.номер === 200 || второйВыход.номер === 404,
    'повторный выход дал неожиданный ответ', 'код ' + второйВыход.номер);
  await запрос('/выйти', { код: код, пропуск: пропуск2 });
  const ходПослеВсех = await запрос('/ход', { код: код, пропуск: пропуск2, действие: 'ходить', карта: 0 });
  проверить(ходПослеВсех.номер === 404, 'в закрытой комнате приняли ход', 'код ' + ходПослеВсех.номер);

  /* ---- 8. Сервер после всего этого обязан быть живым ---- */
  const жив = await здоровье();
  проверить(жив && жив.живой === true, 'сервер не пережил злые запросы');

  console.log('');
  console.log('проверок сделано: ' + проверок);
  if (провалы.length === 0) {
    console.log('=== Итог: сервер выстоял. Чужого не пустили, мусор не принят, карты не утекли ===');
    return;
  }
  console.log('!!! НАЙДЕНО ПЛОХОГО: ' + провалы.length);
  Array.from(new Set(провалы)).forEach(function (п) { console.log('  - ' + п); });
  process.exitCode = 1;
}

главное().catch(function (сбой) {
  console.error('Проверка сорвалась:', сбой.message);
  process.exitCode = 1;
});
