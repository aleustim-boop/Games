const { chromium, подготовитьПодделку } = require('./браузер-робот.js');
const { spawn } = require('child_process');
const fs = require('fs');
const path = require('path');
const os = require('os');
const net = require('net');

const КОРЕНЬ = path.join(__dirname, '..');
const СЛОМАТЬ = process.argv.includes('--сломать');
const числовойДовод = process.argv.slice(2).find((а) => /^\d+$/.test(а));
const ПОРТ = Number(числовойДовод) || 8080;

let всегоПроверок = 0;
let провалов = 0;
function проверить(условие, слова) {
  всегоПроверок++;
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}
const спать = (мс) => new Promise((ф) => setTimeout(ф, мс));

/** Тап по клетке доски по имени поля («e7», «e4»…). */
async function тап(страница, поле) {
  await страница.evaluate((имя) => {
    const клетка = document.querySelector('[data-поле="' + имя + '"]');
    if (клетка) клетка.click();
  }, поле);
}

/** Сделать ход двумя касаниями — откуда и куда, короткая пауза внутри. */
async function сходить(страница, откуда, куда) {
  await тап(страница, откуда);
  await спать(150);
  await тап(страница, куда);
  await спать(200);
}

async function текстСтрокиХода(страница) {
  return страница.evaluate(() => (document.getElementById('строка-хода') || {}).textContent || '');
}

/* =====================================================================
   ВРЕМЕННАЯ КОПИЯ ДЛЯ ЛОМАЮЩЕГО ЗАПУСКА — тот же приём, что и в
   tests/шахматы-первый-взгляд.js: копируем файлы шахмат целиком (чтобы
   не ловить лишние 404 в консоли), портим ОДИН файл — js/шахматы-экран.js.
   ===================================================================== */

/** Копирует файлы шахмат во временную папку ОС. Настоящие файлы проекта
 *  не трогает — только читает. Возвращает путь к папке копии. */
function подготовитьВременнуюПапку() {
  const tmp = path.join(os.tmpdir(), 'шахматы-подсказки-клика-сломать-' + Date.now());
  fs.mkdirSync(path.join(tmp, 'js'), { recursive: true });

  fs.copyFileSync(path.join(КОРЕНЬ, 'шахматы.html'), path.join(tmp, 'шахматы.html'));
  fs.copyFileSync(path.join(КОРЕНЬ, 'style.css'), path.join(tmp, 'style.css'));
  fs.copyFileSync(path.join(КОРЕНЬ, 'style-шахматы.css'), path.join(tmp, 'style-шахматы.css'));
  fs.copyFileSync(path.join(КОРЕНЬ, 'style-коллекция.css'), path.join(tmp, 'style-коллекция.css'));

  const jsПапка = path.join(КОРЕНЬ, 'js');
  for (const файл of fs.readdirSync(jsПапка).filter((f) => f.endsWith('.js'))) {
    fs.copyFileSync(path.join(jsПапка, файл), path.join(tmp, 'js', файл));
  }

  fs.cpSync(path.join(КОРЕНЬ, 'img', 'шахматы'), path.join(tmp, 'img', 'шахматы'), { recursive: true });
  fs.cpSync(path.join(КОРЕНЬ, 'шрифты'), path.join(tmp, 'шрифты'), { recursive: true });

  return tmp;
}

/** Пишет «стало» только если замена реально что-то поменяла — иначе
 *  честно сообщает, что цель не нашлась: врать про «покраснело» нельзя. */
function записатьЕслиИзменилось(результаты, название, файл, было, стало) {
  if (было === стало) {
    результаты.push({ название, успех: false, ошибка: 'замена не нашла цель в ' + path.basename(файл) });
    return;
  }
  fs.writeFileSync(файл, стало, 'utf-8');
  результаты.push({ название, успех: true });
}

/** Портит копию js/шахматы-экран.js по обеим подсказкам разом — откатывает
 *  словаОтказа и убирает показ объяснения поворота к прежнему поведению.
 *  Возвращает список { название, успех, ошибка? }. */
function испортитьКопию(tmp) {
  const результаты = [];
  const файлЭкрана = path.join(tmp, 'js', 'шахматы-экран.js');

  // 1. Подсказка про чужую фигуру и пустую клетку — назад к безликим словам.
  {
    const было = fs.readFileSync(файлЭкрана, 'utf-8');
    const стало = было
      .split("if (что) return 'Сейчас ход ' + (Правила.чейХод(партия) === Правила.БЕЛЫЕ ? 'белых' : 'чёрных');")
      .join("if (что) return 'Сейчас ход другого игрока';")
      .split("return 'Выберите свою фигуру';")
      .join("return 'Сначала выберите свою фигуру';");
    записатьЕслиИзменилось(результаты, 'подсказка про чужую фигуру/пустую клетку (словаОтказа)', файлЭкрана, было, стало);
  }

  // 2. Объяснение поворота доски — убираем сам вызов показатьВременнуюСтроку.
  {
    const было = fs.readFileSync(файлЭкрана, 'utf-8');
    const стало = было
      .split('if (доскаТолькоЧтоПовернулась) показатьВременнуюСтроку(словаОПовороте(), ПОКАЗ_ПОВОРОТА);')
      .join('/* СЛОМАНО (ломающий запуск): объяснение поворота убрано */');
    записатьЕслиИзменилось(результаты, 'объяснение поворота доски (строка-хода на миг)', файлЭкрана, было, стало);
  }

  return результаты;
}

/** Свободный порт для копии — спрашиваем у ОС порт 0. 8790/8791 (боевой
 *  сервер комнат) не трогаем никогда, жёстко прибитого номера тоже нет. */
function свободныйПорт() {
  return new Promise((готово, беда) => {
    const проба = net.createServer();
    проба.unref();
    проба.on('error', беда);
    проба.listen(0, '127.0.0.1', () => {
      const { port } = проба.address();
      проба.close(() => готово(port));
    });
  });
}

/** Поднимает tests/локальный-сервер.js в отдельном процессе на копии. */
function поднятьСервер(tmp, порт) {
  const сервер = spawn('node', [path.join(__dirname, 'локальный-сервер.js'), String(порт)], {
    env: Object.assign({}, process.env, { КОРЕНЬ_СЕРВЕРА: tmp }),
    stdio: 'pipe'
  });

  return new Promise((resolve, reject) => {
    let вывод = '';
    const таймаут = setTimeout(() => reject(new Error('сервер копии не поднялся за 8 секунд')), 8000);
    сервер.stdout.on('data', (д) => {
      вывод += д.toString();
      if (вывод.includes('запущен')) { clearTimeout(таймаут); resolve(сервер); }
    });
    сервер.stderr.on('data', (д) => console.log('  ошибка сервера копии: ' + д.toString().trim()));
    сервер.on('error', (е) => { clearTimeout(таймаут); reject(е); });
  });
}

async function новаяСтраница(браузер, адрес) {
  const окно = await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, deviceScaleFactor: 2 });
  const страница = await окно.newPage();
  страница.setDefaultTimeout(5000);
  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
    красные.push('консоль: ' + м.text());
  });
  страница.on('response', (о) => {
    if (о.status() >= 400) красные.push('сеть: ' + о.status() + ' ' + о.url());
  });

  await подготовитьПодделку(страница, { версия: '8.0' });
  await страница.goto(адрес);
  await спать(700);
  return { окно, страница, красные };
}

/* =====================================================================
   ВСЕ ПРОВЕРКИ — ОДНОЙ ФУНКЦИЕЙ: её же гоняет и чистый, и ломающий запуск.
   ===================================================================== */
async function прогнать(браузер, адрес) {
  /* --------------------------------------------------------------
     1–3. Вдвоём: чужая фигура, пустая клетка, объяснение поворота
     -------------------------------------------------------------- */
  console.log('\n=== Вдвоём: подсказки клика ===');
  {
    const { окно, страница, красные } = await новаяСтраница(браузер, адрес);
    await страница.click('#лобби-вдвоём');
    await спать(400);

    // 1. Клик по чёрной фигуре (e7 — чёрная пешка) на ходу белых.
    await тап(страница, 'e7');
    await спать(200);
    const послеЧужой = await текстСтрокиХода(страница);
    console.log('  клик по чёрной фигуре при ходе белых: «' + послеЧужой + '»');
    проверить(/ход белых/i.test(послеЧужой), 'строка хода содержит «ход белых»: «' + послеЧужой + '»');

    // 2. Клик по пустой клетке (e4 пока пуста) без выбранной фигуры.
    await тап(страница, 'e4');
    await спать(200);
    const послеПустой = await текстСтрокиХода(страница);
    console.log('  клик по пустой клетке без выбора: «' + послеПустой + '»');
    // Точное сравнение, не includes: старый текст «Сначала выберите свою
    // фигуру» тоже содержит подстроку «выберите свою фигуру», и regex-поиск
    // не заметил бы отката к нему — проверка обязана отличать ровно эти слова.
    проверить(послеПустой.trim() === 'Выберите свою фигуру', 'строка хода — ровно «Выберите свою фигуру»: «' + послеПустой + '»');

    // 3. Настоящий ход белых — доска поворачивается к чёрным, строка
    //    хода на миг объясняет это словом «повёрнута».
    await сходить(страница, 'e2', 'e4');
    const послеХода = await текстСтрокиХода(страница);
    console.log('  сразу после хода белых (доска повернулась): «' + послеХода + '»');
    проверить(/повёрнута/i.test(послеХода), 'строка хода содержит «повёрнута»: «' + послеХода + '»');

    проверить(красные.length === 0, 'консоль чистая (вдвоём)' + (красные.length ? ': ' + красные.join(' | ') : ''));
    await окно.close();
  }

  /* --------------------------------------------------------------
     4. С ботом: клик по фигуре бота на своём ходе — то же правило
     -------------------------------------------------------------- */
  console.log('\n=== С ботом: клик по фигуре бота ===');
  {
    const { окно, страница, красные } = await новаяСтраница(браузер, адрес);
    await страница.click('#лобби-боты');
    await спать(200);
    await страница.click('#лобби-уровень-лёгкий');
    await спать(200);
    await страница.click('#лобби-бот-начать');
    await спать(500);

    await тап(страница, 'e7');   // чёрная фигура бота, а ход всё ещё белых (человека)
    await спать(200);
    const послеФигурыБота = await текстСтрокиХода(страница);
    console.log('  клик по фигуре бота на своём ходе: «' + послеФигурыБота + '»');
    проверить(/ход белых/i.test(послеФигурыБота), 'строка хода содержит «ход белых»: «' + послеФигурыБота + '»');

    проверить(красные.length === 0, 'консоль чистая (с ботом)' + (красные.length ? ': ' + красные.join(' | ') : ''));
    await окно.close();
  }

  return { всегоПроверок, провалов };
}

/* =====================================================================
   ЗАПУСК
   ===================================================================== */
(async () => {
  const браузер = await chromium.launch();

  if (!СЛОМАТЬ) {
    const АДРЕС = 'http://127.0.0.1:' + ПОРТ + '/шахматы.html';
    console.log('Шахматы — подсказки клика. Страница: ' + АДРЕС);
    await прогнать(браузер, АДРЕС);
    await браузер.close();
    console.log('\n=== ИТОГ ОСНОВНЫХ ПРОВЕРОК ===');
    console.log('Итого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
    process.exit(провалов ? 1 : 0);
  }

  // ============= ЛОМАЮЩИЙ ЗАПУСК =============
  console.log('\n=== ЛОМАЮЩИЙ ЗАПУСК: портим копию, гоняем те же проверки ===');
  let процессСервера = null;
  try {
    const tmp = подготовитьВременнуюПапку();
    console.log('Временная папка (не удаляется — чистится сама ОС): ' + tmp);

    console.log('\nПортим копию по обеим подсказкам...');
    const поломки = испортитьКопию(tmp);
    let всеПрименились = true;
    for (const п of поломки) {
      if (п.успех) {
        console.log('  ✓ поломка применилась: ' + п.название);
      } else {
        console.log('  ✗ ОШИБКА: поломка НЕ применилась: ' + п.название + ' (' + п.ошибка + ')');
        всеПрименились = false;
      }
    }
    if (!всеПрименились) {
      console.log('\n=== ПРОВАЛ СТЕНДА: не все поломки применились — ломающий запуск не может ручаться за результат ===');
      await браузер.close();
      process.exit(2);
    }

    const порт = await свободныйПорт();
    console.log('\nПоднимаем сервер копии на порту ' + порт + '...');
    процессСервера = await поднятьСервер(tmp, порт);
    await спать(300);

    const АДРЕС_КОПИИ = 'http://127.0.0.1:' + порт + '/шахматы.html';
    console.log('Гоняем те же проверки по копии: ' + АДРЕС_КОПИИ);
    await прогнать(браузер, АДРЕС_КОПИИ);

    await браузер.close();
    процессСервера.kill();

    console.log('\n=== ИТОГ ЛОМАЮЩЕГО ЗАПУСКА ===');
    console.log('Итого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
    if (провалов === 0) {
      console.log('ПРОВЕРКА СЛЕПАЯ: порча внесена, а ни одна проверка не покраснела.');
      process.exit(1);
    }
    process.exit(1); // ломающий запуск обязан завершиться кодом 1 — он и должен провалиться
  } catch (ошибка) {
    console.error('\nЛомающий запуск упал: ' + (ошибка && ошибка.stack || ошибка));
    if (процессСервера) процессСервера.kill();
    await браузер.close();
    process.exit(2);
  }
})();
