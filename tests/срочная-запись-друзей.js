#!/usr/bin/env node
'use strict';

/* =====================================================================
   СРОЧНАЯ ЗАПИСЬ ДРУЗЕЙ И ЗНАКОМЫХ: заявка в друзья и запись знакомства
   должны лечь на диск сразу, а не через пять секунд.

   Та же беда, что уже чинилась в server/рейтинг.js, server/сила-игроков.js
   и server/раздача-дня.js (см. tests/срочная-запись-рейтинга.js,
   tests/срочная-запись-силы.js, tests/срочная-запись-раздачи.js), нашлась
   и здесь: обе памяти меняются в памяти процесса сразу, а на диск падают
   отложенно (ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ = 5000). Падение сервера в эти пять секунд
   стирает свежую заявку или знакомство.

   ПОЧЕМУ ОДНА ПРОВЕРКА НА ОБА ФАЙЛА. В обоих деления «важное/мелочь»
   не нашлось — оно есть только в накопительном рейтинге (там партия
   с нулевой ценой и вправду не меняет то, что видит игрок). Здесь иначе:
     — друзья.js: позвать, принять, отклонить, удалить — каждое действие
       тут же видно на экране (список друзей, входящие заявки), повторять
       его человеку обидно;
     — знакомые.js: запись знакомства видна в разделе «Позвать знакомого»
       внутри комнаты (js/дурак-комната.js) и на экране добавления друзей
       (js/друзья-экран.js) — раздали карты, кто-то тут же открыл новую
       комнату и хочет позвать только что встреченного человека.
   Тело функции записатьСрочно() у обоих файлов получилось буквально
   одинаковым, поэтому и приём порчи, и приём проверки один и тот же —
   разница только в том, какой модуль грузим и что в него передаём.

   КАК ПРОВЕРЯЕМ «упало сразу после действия», не дожидаясь настоящего
   падения и не ожидая реальных пяти секунд: действие делается в
   ОТДЕЛЬНОМ процессе node, который завершается через process.exit(0)
   сразу после него — без вызова дописать(). Если запись была синхронной
   (writeFileSync успел отработать до exit) — файл на диске есть с нужными
   данными. Если код вернулся к старой отложенной схеме — файла нет вовсе.

   УМЕЕТ ЛИ ОНА КРАСНЕТЬ. node tests/срочная-запись-друзей.js --сломать
   берёт временные копии server/друзья.js и server/знакомые.js и подменяет
   тело записатьСрочно() на пятисекундный setTimeout (.unref(), как было
   раньше) — ровно та регрессия, от которой предостерегал штаб. На такой
   копии оба сценария обязаны провалиться: сразу после «падения» файлов
   ещё не будет.

   Боевых данных не касается: копия server/ и папка данных — во временных
   каталогах (mkdtempSync), каждое действие считается в отдельном дочернем
   процессе node, чтобы «падение сразу после exit» было настоящим,
   а не догадкой по логике кода.

   Запуск:
     node tests/срочная-запись-друзей.js             (обычный прогон)
     node tests/срочная-запись-друзей.js --сломать   (обязан провалиться)
   Выход 0 — провалов нет, 1 — провал (смотреть строки «ПРОВАЛ» в выводе).
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const СЛОМАТЬ = process.argv.includes('--сломать');

const ПРОВЕРКИ = [];
function проверить(имя, условие, подробности) {
  ПРОВЕРКИ.push({ имя: имя, ошибка: условие ? null : (подробности || 'условие не выполнено') });
}

/* Все временные папки этого прогона (копия server/+js/ и по одной у
   каждого дочернего раннера) — чтобы убрать их за собой в самом конце,
   а не оставлять мусор во временной папке ОС на каждый запуск. */
const ВСЕ_ВРЕМЕННЫЕ_ПАПКИ = [];

/** Своя временная папка с заданным префиксом — и сразу на учёт для уборки. */
function новаяВременнаяПапка(префикс) {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), префикс));
  ВСЕ_ВРЕМЕННЫЕ_ПАПКИ.push(папка);
  return папка;
}

/* Убираем СВОИ временные папки по любому выходу процесса —
   process.on('exit') срабатывает и на process.exit(), и на непойманную
   ошибку. Раньше эти папки никогда не удалялись и копились на диске. */
process.on('exit', function () {
  for (const папка of ВСЕ_ВРЕМЕННЫЕ_ПАПКИ) {
    try { fs.rmSync(папка, { recursive: true, force: true, maxRetries: 3 }); } catch (е) { /* не страшно */ }
  }
});

/**
 * Своя копия server/ и js/ во временной папке — боевой код и боевые данные
 * не трогаем. js/ нужен и знакомые.js: он требует server/игры/реестр.js,
 * а тот через server/партия-по-сети.js доходит до require('../js/game.js') —
 * сервер всегда стартует из рабочей папки, где js/ лежит рядом с server/.
 */
function подготовитьКопиюСервера() {
  const врем = новаяВременнаяПапка('срочная-запись-друзей-');
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(врем, 'server'), { recursive: true });
  fs.cpSync(path.join(КОРЕНЬ, 'js'), path.join(врем, 'js'), { recursive: true });
  return {
    друзья: path.join(врем, 'server', 'друзья.js'),
    знакомые: path.join(врем, 'server', 'знакомые.js')
  };
}

/**
 * Порча копии: возвращает записатьСрочно() обратно к пятисекундному
 * отложенному письму (тот же .unref(), что был раньше у записатьпогодя) —
 * ровно регрессия, о которой предупреждал штаб. Тело функции у обоих
 * файлов одинаковое, поэтому одна и та же порча годится для обоих путей.
 */
function испортитьКопию(путьКФайлу) {
  const исходник = fs.readFileSync(путьКФайлу, 'utf8');
  const было = 'function записатьСрочно() {\n' +
    '  if (!записьРазрешена) return;\n' +
    '  естьЧтоЗаписать = true;\n' +
    '  записатьСейчас();\n' +
    '}';
  if (исходник.indexOf(было) === -1) {
    throw new Error('не нашёл тело записатьСрочно() для порчи — код ' + путьКФайлу
      + ' изменился, поправьте tests/срочная-запись-друзей.js');
  }
  const испорчено = исходник.replace(было,
    'function записатьСрочно() {\n' +
    '  if (!записьРазрешена) return;\n' +
    '  естьЧтоЗаписать = true;\n' +
    '  /* ИСПОРЧЕНО ПРОВЕРКОЙ tests/срочная-запись-друзей.js --сломать: снова ждём 5 секунд */\n' +
    '  var т = setTimeout(function () { записатьСейчас(); }, 5000);\n' +
    '  if (т.unref) т.unref();\n' +
    '}');
  fs.writeFileSync(путьКФайлу, испорчено, 'utf8');
}

/** Запустить код раннера в отдельном процессе и вернуть, что осталось на диске в файле. */
function выполнитьВОтдельномПроцессе(строкиРаннера, имяФайлаПамяти) {
  const врем = новаяВременнаяПапка('срочная-запись-друзей-раннер-');
  const папкаДанных = path.join(врем, 'данные');
  const файлРаннера = path.join(врем, 'раннер.js');
  fs.writeFileSync(файлРаннера, [
    "process.env.GAMES_DATA = " + JSON.stringify(папкаДанных) + ";"
  ].concat(строкиРаннера).join('\n'), 'utf8');

  execFileSync(process.execPath, [файлРаннера], { stdio: 'pipe' });

  const файлПамяти = path.join(папкаДанных, имяФайлаПамяти);
  if (!fs.existsSync(файлПамяти)) return null;
  return JSON.parse(fs.readFileSync(файлПамяти, 'utf8'));
}

/* -----------------------------------------------------------------------
   Сценарий 1: друзья.js — позвать в друзья.
   ----------------------------------------------------------------------- */

function проверитьДрузей(путьКДрузьям) {
  const данные = выполнитьВОтдельномПроцессе([
    "const друзья = require(" + JSON.stringify(путьКДрузьям) + ");",
    "друзья.включитьЗапись();",
    "друзья.позватьВДрузья(5001, 5002);",
    "process.exit(0);"
  ], 'друзья.json');

  const связь = данные && Array.isArray(данные.связи)
    ? данные.связи.find(function (с) { return с.первый === 5001 && с.второй === 5002; })
    : null;

  проверить(
    'заявка в друзья есть на диске сразу после «падения» процесса',
    !!связь && связь.статус === 'ожидает' && связь.кто_позвал === 5001,
    данные === null
      ? 'файл друзья.json вообще не появился — заявка потерялась, как и предупреждал штаб'
      : 'на диске: ' + JSON.stringify(связь) + ' (ждали статус «ожидает», кто_позвал 5001)'
  );
}

/* -----------------------------------------------------------------------
   Сценарий 2: знакомые.js — запомнить застолье.
   ----------------------------------------------------------------------- */

function проверитьЗнакомых(путьКЗнакомым) {
  const застолье = [
    { номер: 6001, имя: 'Аня' },
    { номер: 6002, имя: 'Боря' }
  ];
  const данные = выполнитьВОтдельномПроцессе([
    "const знакомые = require(" + JSON.stringify(путьКЗнакомым) + ");",
    "знакомые.включитьЗапись();",
    "знакомые.запомнитьЗастолье(" + JSON.stringify(застолье) + ", 'дурак');",
    "process.exit(0);"
  ], 'знакомые.json');

  const запись = данные && Array.isArray(данные.знакомства)
    ? данные.знакомства.find(function (з) { return з.первый === 6001 && з.второй === 6002; })
    : null;

  проверить(
    'знакомство есть на диске сразу после «падения» процесса',
    !!запись && запись.имяПервого === 'Аня' && запись.имяВторого === 'Боря',
    данные === null
      ? 'файл знакомые.json вообще не появился — знакомство потерялось, как и предупреждал штаб'
      : 'на диске: ' + JSON.stringify(запись) + ' (ждали имена Аня и Боря)'
  );
}

/* -----------------------------------------------------------------------
   main
   ----------------------------------------------------------------------- */

const пути = подготовитьКопиюСервера();
if (СЛОМАТЬ) {
  испортитьКопию(пути.друзья);
  испортитьКопию(пути.знакомые);
}

проверитьДрузей(пути.друзья);
проверитьЗнакомых(пути.знакомые);

console.log('');
let провалов = 0;
for (const п of ПРОВЕРКИ) {
  if (п.ошибка) {
    провалов++;
    console.log('  ПРОВАЛ ' + п.имя + ': ' + п.ошибка);
  } else {
    console.log('  ок     ' + п.имя);
  }
}
console.log('');
console.log('Итого проверок: ' + ПРОВЕРКИ.length + ', провалов: ' + провалов);
process.exit(провалов > 0 ? 1 : 0);
