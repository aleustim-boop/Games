/* Проверка этапа Э7 (штаб/план-живые-лобби.md): в списке открытых столов
   перед именами рисуется ряд кружков с фото сидящих.

   Запуск:  node tests/открытые-столы-портреты.js
   Проверяемый файл можно подсунуть доводом (так делают ломающие запуски):
            node tests/открытые-столы-портреты.js <путь к копии открытые-столы.js>

   Без довода проверка сама делает две порченые копии во временной папке
   (настоящий файл не трогаем) и требует, чтобы на каждой проверка
   провалилась. Ноль найденного — тоже провал, а не пропуск. */

'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const vm = require('vm');
const { execFileSync } = require('child_process');

const ЖИВОЙ_ФАЙЛ = path.join(__dirname, '..', 'js', 'открытые-столы.js');
const АДРЕС = 'https://сервер.пример';
const К1 = 'a1b2c3d4e5f60718293a4b5c';
const К2 = '00112233445566778899aabb';

/* ---------- поддельный DOM: ровно столько, сколько нужно файлу ---------- */

function создатьДокумент() {
  const делегаты = [];   // подписки на «error» и «click», чтобы проверка могла их вызвать

  function Элемент(тег) {
    this.tagName = тег.toUpperCase();
    this.id = '';
    this.className = '';
    this.children = [];
    this.parentNode = null;
    this.обработчики = {};
    this.disabled = false;
    this.внутриРазметкой = false;   // поднимется, если файл пишет в innerHTML
    this._текст = '';
    const сам = this;
    this.classList = {
      add(к) { if (!сам.classList.contains(к)) сам.className = (сам.className + ' ' + к).trim(); },
      remove(к) { сам.className = сам.className.split(/\s+/).filter(function (х) { return х && х !== к; }).join(' '); },
      contains(к) { return сам.className.split(/\s+/).indexOf(к) !== -1; },
      toggle(к, вкл) { if (вкл) сам.classList.add(к); else сам.classList.remove(к); }
    };
  }
  Элемент.prototype = {
    get textContent() { return this._текст; },
    set textContent(в) { this._текст = String(в); this.children = []; },
    get innerHTML() { return ''; },
    set innerHTML(в) { this.внутриРазметкой = true; this._текст = String(в); },
    get firstChild() { return this.children[0] || null; },
    appendChild(ребёнок) { ребёнок.parentNode = this; this.children.push(ребёнок); return ребёнок; },
    removeChild(ребёнок) {
      const и = this.children.indexOf(ребёнок);
      if (и !== -1) this.children.splice(и, 1);
      ребёнок.parentNode = null;
      return ребёнок;
    },
    replaceChild(новый, старый) {
      const и = this.children.indexOf(старый);
      if (и === -1) throw new Error('replaceChild: такого ребёнка нет');
      this.children[и] = новый;
      новый.parentNode = this;
      старый.parentNode = null;
      return старый;
    },
    addEventListener(имя, действие) { (this.обработчики[имя] = this.обработчики[имя] || []).push(действие); },
    setAttribute() {},
    click() {}
  };

  const корень = new Элемент('div');
  корень.id = 'приложение';

  function найтиПоId(узел, id) {
    if (узел.id === id) return узел;
    for (const р of узел.children) {
      const найден = найтиПоId(р, id);
      if (найден) return найден;
    }
    return null;
  }

  return {
    корень: корень,
    делегаты: делегаты,
    document: {
      readyState: 'complete',
      body: корень,
      createElement(тег) { return new Элемент(тег); },
      getElementById(id) { return найтиПоId(корень, id); },
      querySelector() { return null; },
      querySelectorAll() { return []; },
      addEventListener() {}
    }
  };
}

function обойти(узел, действие) {
  действие(узел);
  for (const р of узел.children) обойти(р, действие);
}

/* ---------- прогон: открыть экран с готовым ответом сервера ---------- */

async function нарисоватьСписок(путьКФайлу, столы) {
  const дом = создатьДокумент();
  const окно = {
    Сеть: {
      адрес() { return АДРЕС; },
      открытыеСтолы() { return Promise.resolve({ ок: true, узналиВас: true, столы: столы }); }
    },
    ИграСтраницы: 'шашки'
  };
  const песочница = {
    window: окно,
    document: дом.document,
    setInterval() { return 1; },
    clearInterval() {},
    Date: Date,
    Number: Number, String: String, Array: Array, Math: Math, Boolean: Boolean, Error: Error
  };
  окно.document = дом.document;
  vm.createContext(песочница);
  vm.runInContext(fs.readFileSync(путьКФайлу, 'utf8'), песочница, { filename: путьКФайлу });
  if (!окно.ЭкранОткрытыхСтолов) throw new Error('файл не выставил window.ЭкранОткрытыхСтолов');
  окно.ЭкранОткрытыхСтолов.открыть();
  await new Promise(function (р) { setImmediate(р); });
  const список = дом.document.getElementById('открытые-столы-список');
  if (!список) throw new Error('узел списка не появился');
  return { список: список, дом: дом };
}

/* ---------- проверки ---------- */

let всего = 0;
let упало = 0;

function проверить(что, условие, подробность) {
  всего++;
  if (условие) {
    console.log('  ок   ' + что);
  } else {
    упало++;
    console.log('  ПРОВАЛ ' + что + (подробность ? ' — ' + подробность : ''));
  }
}

function картинкиСтроки(строка) {
  const найдено = [];
  обойти(строка, function (у) { if (у.tagName === 'IMG') найдено.push(у); });
  return найдено;
}

function силуэтыСтроки(строка) {
  const найдено = [];
  обойти(строка, function (у) {
    if (у.classList && у.classList.contains('открытые-столы__лицо--пусто')) найдено.push(у);
  });
  return найдено;
}

function ряд(строка) {
  return строка.children.find(function (у) { return у.classList.contains('открытые-столы__лица'); }) || null;
}

async function главная(путьКФайлу) {
  /* 1. Два портрета — две картинки с нужными адресами, ряд стоит первым. */
  {
    const { список } = await нарисоватьСписок(путьКФайлу, [
      { ключ: 'с1', занято: 2, мест: 2, игроки: ['Аня', 'Боря'], портреты: [К1, К2], ждётСекунд: 5 }
    ]);
    const строка = список.children[0];
    проверить('1: строка стола нарисована', Boolean(строка), 'строк в списке: ' + список.children.length);
    if (строка) {
      const картинки = картинкиСтроки(строка);
      проверить('1: две картинки', картинки.length === 2, 'найдено: ' + картинки.length);
      проверить('1: адрес первой — ' + АДРЕС + '/фото/<ключ>', картинки[0] && картинки[0].src === АДРЕС + '/фото/' + К1,
        картинки[0] && картинки[0].src);
      проверить('1: адрес второй', картинки[1] && картинки[1].src === АДРЕС + '/фото/' + К2,
        картинки[1] && картинки[1].src);
      проверить('1: силуэтов нет', силуэтыСтроки(строка).length === 0);
      проверить('1: ряд кружков идёт перед ячейками с именами', строка.children[0] === ряд(строка));
      проверить('1: у картинки пустой alt (имя уже написано рядом)', картинки[0] && картинки[0].alt === '');
    }
  }

  /* 2. Пустой, пропавший и негодный ключ — силуэт; годный рядом — картинка. */
  {
    const { список } = await нарисоватьСписок(путьКФайлу, [
      { ключ: 'с2', занято: 4, мест: 4, игроки: ['А', 'Б', 'В', 'Г'], портреты: [К1, null, '', '../../x'], ждётСекунд: 70 }
    ]);
    const строка = список.children[0];
    if (!строка) {
      проверить('2: строка нарисована', false);
    } else {
      проверить('2: одна картинка (годный ключ)', картинкиСтроки(строка).length === 1,
        'найдено: ' + картинкиСтроки(строка).length);
      проверить('2: три силуэта (null, пустой, негодный)', силуэтыСтроки(строка).length === 3,
        'найдено: ' + силуэтыСтроки(строка).length);
    }
  }

  /* 3. Ошибка загрузки картинки — на её место встаёт силуэт. */
  {
    const { список } = await нарисоватьСписок(путьКФайлу, [
      { ключ: 'с3', занято: 1, мест: 2, игроки: ['Лена'], портреты: [К1], ждётСекунд: 5 }
    ]);
    const строка = список.children[0];
    const картинки = строка ? картинкиСтроки(строка) : [];
    проверить('3: картинка есть до ошибки', картинки.length === 1);
    const обработчики = картинки[0] && картинки[0].обработчики.error;
    проверить('3: на картинке висит обработчик ошибки', Boolean(обработчики && обработчики.length));
    if (обработчики && обработчики.length) {
      обработчики[0]();
      проверить('3: после ошибки картинок нет', картинкиСтроки(строка).length === 0);
      проверить('3: после ошибки стоит силуэт', силуэтыСтроки(строка).length === 1);
    }
  }

  /* 4. Имя с «<b>» — только текст, разметкой не становится. */
  {
    const { список, дом } = await нарисоватьСписок(путьКФайлу, [
      { ключ: 'с4', занято: 2, мест: 2, игроки: ['<b>Злой</b>', 'Тихий'], портреты: [К1, null], ждётСекунд: 5 }
    ]);
    const строка = список.children[0];
    let ячейкаИмён = null;
    if (строка) обойти(строка, function (у) { if (у.classList && у.classList.contains('таблица__очки')) ячейкаИмён = у; });
    проверить('4: ячейка с именами найдена', Boolean(ячейкаИмён));
    проверить('4: имя лежит текстом как есть',
      ячейкаИмён && ячейкаИмён.textContent === '<b>Злой</b>, Тихий', ячейкаИмён && ячейкаИмён.textContent);
    let записаноРазметкой = 0;
    обойти(дом.корень, function (у) { if (у.внутриРазметкой) записаноРазметкой++; });
    проверить('4: в innerHTML ничего не писали', записаноРазметкой === 0, 'узлов с разметкой: ' + записаноРазметкой);
    let тегB = 0;
    обойти(дом.корень, function (у) { if (у.tagName === 'B') тегB++; });
    проверить('4: тега <b> в дереве нет', тегB === 0);
  }

  /* 5. Стол без поля «портреты» (старый сервер) — строка рисуется, ряда нет. */
  {
    const { список } = await нарисоватьСписок(путьКФайлу, [
      { ключ: 'с5', занято: 1, мест: 2, игроки: ['Олег'], ждётСекунд: 5 }
    ]);
    const строка = список.children[0];
    проверить('5: строка без портретов нарисована', Boolean(строка));
    проверить('5: ряда кружков нет', строка && ряд(строка) === null);
  }
}

/* ---------- ломающие запуски на копиях во временной папке ---------- */

function порченаяКопия(имя, было, стало) {
  const исходник = fs.readFileSync(ЖИВОЙ_ФАЙЛ, 'utf8');
  if (исходник.indexOf(было) === -1) {
    console.log('  ПРОВАЛ ломающий «' + имя + '»: нечего портить, строки «' + было + '» в файле нет');
    return null;
  }
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'столы-портреты-'));
  const копия = path.join(папка, 'открытые-столы.js');
  fs.writeFileSync(копия, исходник.split(было).join(стало), 'utf8');
  return копия;
}

function долженКраснеть(имя, было, стало) {
  всего++;
  const копия = порченаяКопия(имя, было, стало);
  if (!копия) { упало++; return; }
  let код = 0;
  try {
    execFileSync(process.execPath, [__filename, копия], { stdio: 'pipe' });
  } catch (сбой) {
    код = сбой.status || 1;
  }
  if (код !== 0) {
    console.log('  ок   ломающий «' + имя + '» покраснел (код ' + код + ')');
  } else {
    упало++;
    console.log('  ПРОВАЛ ломающий «' + имя + '» НЕ покраснел — проверка не умеет краснеть');
  }
}

/* ---------- запуск ---------- */

(async function () {
  const довод = process.argv[2];
  const путь = довод ? path.resolve(довод) : ЖИВОЙ_ФАЙЛ;
  console.log('Проверяю файл: ' + путь);
  try {
    await главная(путь);
  } catch (сбой) {
    упало++;
    всего++;
    console.log('  ПРОВАЛ прогон упал: ' + (сбой && сбой.message));
  }

  if (!довод) {
    долженКраснеть('выкинута отрисовка кружков',
      'строка.appendChild(рядЛиц(стол.портреты));', 'void 0;');
    долженКраснеть('имена через innerHTML',
      'элемент.textContent = текст;', 'элемент.innerHTML = текст;');
    долженКраснеть('нет силуэта при ошибке загрузки',
      'картинка.parentNode.replaceChild(силуэт(), картинка);', 'void 0;');
  }

  console.log('\nИтого проверок: ' + всего + ', провалов: ' + упало);
  process.exit(упало === 0 ? 0 : 1);
})();
