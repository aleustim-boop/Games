/** Скопировать server/ и js/ во временную папку (без данных игроков). */
function сделатьКопию(папка) {
  for (const часть of ['server', 'js']) {
    fs.cpSync(path.join(ПРОЕКТ, часть), path.join(папка, часть), {
      recursive: true,
      filter: function (откуда) {
        const имя = path.basename(откуда);
        return имя !== 'данные' && имя !== 'node_modules';
      }
    });
  }
}

function заменитьРовноОдинРаз(текст, найти, заменить) {
  const где = текст.indexOf(найти);
  if (где === -1) return null;
  return текст.slice(0, где) + заменить + текст.slice(где + найти.length);
}

function ломать() {
  console.log('=== Ломающие прогоны подбора шашек и нард: каждая порча обязана покраснеть ===');
  const общая = fs.mkdtempSync(path.join(os.tmpdir(), 'подбор-игр-лом-'));
  console.log('копии в ' + общая + '\n');
  let проверок = 0;
  const провалы = [];

  for (const порча of ПОРЧИ) {
    проверок++;
    const папка = path.join(общая, порча.имя);
    сделатьКопию(папка);
    const файл = path.join(папка, 'server', 'сервер.js');
    let текст = fs.readFileSync(файл, 'utf8');
    текст = заменитьРовноОдинРаз(текст, порча.найти, порча.заменить);
    if (текст !== null && порча.найти2) текст = заменитьРовноОдинРаз(текст, порча.найти2, порча.заменить2);
    if (текст === null) {
      провалы.push(порча.имя + ': место порчи в сервер.js не найдено — проверку не на чем покраснить');
      console.log('  ПРОВАЛ ' + порча.имя + ': место порчи не найдено');
      continue;
    }
    fs.writeFileSync(файл, текст, 'utf8');

    const прогон = spawnSync(process.execPath, [__filename, '--корень', папка], {
      encoding: 'utf8', timeout: 180000
    });
    const вывод = (прогон.stdout || '') + (прогон.stderr || '');
    const красные = new Set();
    const найдено = вывод.match(/ПРОВАЛ \[[А-Я]\]/g) || [];
    найдено.forEach(function (с) { красные.add(с.slice(8, 9)); });
    const недостаёт = порча.краснеют.filter(function (б) { return !красные.has(б); });
    const ок = прогон.status === 1 && недостаёт.length === 0;
    console.log((ок ? '  красная, как надо: ' : '  ПРОВАЛ (осталась зелёной): ') + порча.имя +
                ' — ' + порча.что + '; код выхода ' + прогон.status +
                ', покраснели буквы: ' + (Array.from(красные).join(', ') || 'ни одна'));
    if (!ок) {
      провалы.push(порча.имя + ': ждали красные ' + порча.краснеют.join(', ') +
                   ', не покраснели ' + (недостаёт.join(', ') || '—') + ', код выхода ' + прогон.status);
    }
  }

  console.log('\n----------------------------------------');
  for (const беда of провалы) console.log('  - ' + беда);
  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалы.length);
  console.log('Копии оставлены для разбора: ' + общая);
  process.exit(провалы.length > 0 ? 1 : 0);
}

