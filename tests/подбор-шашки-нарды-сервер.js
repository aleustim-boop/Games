  console.log('А. Двое «шашки» сведены за стол шашек');
  await сверитьПару('А', 'шашки', [501, 'Аня'], [502, 'Боря']);

  console.log('Б. Двое «нарды» сведены за стол нард');
  await сверитьПару('Б', 'нарды', [503, 'Вера'], [504, 'Гоша']);

  console.log('В. Очереди раздельные: шашки не встречаются с дураком и нардами');
  const шашки = await встать(505, 'Даша', { игра: 'шашки' });
  const дурак = await встать(506, 'Егор', { игра: 'дурак' });
  const нарды = await встать(507, 'Женя', { игра: 'нарды' });
  проверить('В', шашки.тело.статус === 'ждёт', 'шашки ждут в своей очереди');
  проверить('В', дурак.тело.статус === 'ждёт', 'дурак после шашек не сведён с ними, ждёт');
  проверить('В', нарды.тело.статус === 'ждёт', 'нарды после шашек и дурака не сведены с ними, ждут');
  for (const о of [шашки, дурак, нарды]) {
    if (о.тело.ключОжидания) await отменить(о.тело.ключОжидания);
  }

  console.log('Г. «Переводной» у шашек обнуляется: очередь не делится');
  const спереводным = await встать(508, 'Зоя', { игра: 'шашки', переводной: true });
  const безНего = await встать(509, 'Илья', { игра: 'шашки', переводной: false });
  проверить('Г', спереводным.тело.статус === 'ждёт', 'шашки с переводной:true ждут');
  проверить('Г', безНего.тело.статус === 'свели',
    'шашки без переводного сведены с ними — «переводной» шашкам не делит очередь');
  if (безНего.тело.статус !== 'свели') {
    for (const о of [спереводным, безНего]) {
      if (о.тело.ключОжидания) await отменить(о.тело.ключОжидания);
    }
  } else if (спереводным.тело.ключОжидания) {
    await новости(спереводным.тело.ключОжидания);   // забрать свой стол, чтобы не висел
  }

  console.log('Д. Одиночке подсаживают бота своей игры и своего уровня');
  подбор.подменитьПорогОжиданияДляПроверки(300);
