'use strict';

/* =====================================================================
   ПРОВЕРКА: нижние вкладки закрывают шторки рейтинга (правка ревьюера,
   партия 7 плана «рейтинг»).

   ПОЧЕМУ ЭТА ПРОВЕРКА НУЖНА. На экране рейтинга у игрока может быть
   открыта панель выбора игры или шторка «инфо» (обе position: fixed на
   всю страницу). Если в этот момент нажать нижнюю вкладку «Игры» или
   «Профиль» (действия 'к-играм-рейтинг' и 'мой-счёт-рейтинг',
   js/нижние-вкладки.js), экран рейтинга прячется/сменяется НАПРЯМУЮ,
   минуя дверь «назад» самого экрана рейтинга — и шторка оставалась бы
   висеть поверх лобби или профиля. Правка зовёт защищённый
   window.ЭкранРейтинга.закрытьПанели() в самом начале обоих действий,
   ДО того, как экран спрятан или нажата чужая дверь.

   ПРИЁМ. Тот же, что в tests/карта-входов-в-рейтинг.js: поднимаем
   НАСТОЯЩИЙ js/нижние-вкладки.js в песочнице vm с поддельным
   <nav data-вкладки="рейтинг"> и поддельными window/document. Файл сам
   заполняет полосу при загрузке (document.querySelectorAll находит наш
   единственный nav) и вешает обработчики на найденные через
   nav.querySelector(...) поддельные кнопки-действия.
   Единственный источник правды о ПОРЯДКЕ событий — общий ЖУРНАЛ: каждая
   поддельная дверь при вызове пишет туда свою метку, а проверки просто
   сравнивают индексы меток (раньше — меньше индекс, -1 — вовсе не было).

   Запуск:
       node tests/нижние-вкладки-закрывают-панели.js            — обычный
         прогон, ждём 0 провалов.
       node tests/нижние-вкладки-закрывают-панели.js --сломать  — ломающий
         прогон: копирует js/нижние-вкладки.js во временную папку
         (os.tmpdir(), настоящий файл проекта не трогает ни на секунду),
         убирает из копии оба вызова закрытьШторкиРейтинга() по точной
         строке (строка не нашлась — падаем с кодом 1, «приём порчи
         устарел») и требует, чтобы проверки порядка для 'к-играм-рейтинг'
         и 'мой-счёт-рейтинг' покраснели. Не покраснели — прогон сам себя
         объявляет слепым.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const os = require('os');
const vm = require('vm');

const КОРЕНЬ = path.join(__dirname, '..');
const ПУТЬ_НАСТОЯЩИЙ = path.join(КОРЕНЬ, 'js', 'нижние-вкладки.js');
const сломать = process.argv.indexOf('--сломать') !== -1;

/**
 * Поднять js/нижние-вкладки.js (по указанному пути на диске — либо
 * настоящий файл, либо испорченная копия) в песочнице vm с поддельным
 * <nav data-вкладки="рейтинг"> и поддельным окружением.
 *
 * ОПЦИИ:
 *   естьЭкранРейтинга  — держит ли window.ЭкранРейтинга вообще (по
 *                         умолчанию true); false — страница, где модуль
 *                         рейтинга не подключён (пункт «г» задания).
 *   сЗакрытьПанели      — есть ли у window.ЭкранРейтинга метод
 *                         закрытьПанели (по умолчанию true); false —
 *                         СТАРЫЙ js/рейтинг-экран.js без этой правки
 *                         (пункт «в» задания).
 *   естьКнопкаЛобби     — есть ли в разметке «кнопка-лобби-назад» (по
 *                         умолчанию true; шашки/шахматы/нарды).
 *   естьКнопкаМойСчёт   — есть ли в разметке «кнопка-мой-счёт» (по
 *                         умолчанию true; она есть только на index.html).
 *   путьСтраницы        — window.location.pathname, нужен действию
 *                         'мой-счёт-рейтинг' без кнопки-мой-счёт, чтобы
 *                         узнать игру по адресу (по умолчанию '/').
 */
function поднятьНижниеВкладки(путь, опции) {
  опции = опции || {};
  const исходник = fs.readFileSync(путь, 'utf8');
  const журнал = [];        // порядок событий — единственный источник правды
  let закрытьПанелиВызовов = 0;

  // <nav data-вкладки="рейтинг"> — querySelector отдаёт поддельную кнопку
  // на каждое найденное «data-нижняя-вкладка-действие», addEventListener
  // запоминает обработчик, click() его вызывает (как настоящий клик).
  const действия = {};
  const navРейтинг = {
    getAttribute(атрибут) { return атрибут === 'data-вкладки' ? 'рейтинг' : null; },
    innerHTML: '',
    querySelector(селектор) {
      const совпадение = /data-нижняя-вкладка-действие="([^"]+)"/.exec(селектор || '');
      if (!совпадение) return null;
      const имяДействия = совпадение[1];
      if (!действия[имяДействия]) {
        const слушатели = [];
        действия[имяДействия] = {
          addEventListener(тип, ф) { слушатели.push(ф); },
          click() { слушатели.slice().forEach(ф => ф()); }
        };
      }
      return действия[имяДействия];
    }
  };

  // Узел «экран-рейтинга-игроков» — спрятатьЭкран() снимает с него класс
  // «экран--виден» (это класс экрана, а не id узла — журналим по узлу,
  // а не по имени переданного класса, иначе метка не совпала бы с id).
  const узелЭкранаРейтинга = {
    classList: {
      remove() { журнал.push('спрятатьЭкран:экран-рейтинга-игроков'); },
      add() {}, toggle() {}, contains() { return false; }
    }
  };

  // «Кнопка-лобби-назад» в шапке лобби шашек/шахмат/нард.
  const слушателиКнопкиЛобби = [];
  const кнопкаЛоббиНазад = {
    addEventListener(тип, ф) { слушателиКнопкиЛобби.push(ф); },
    click() {
      журнал.push('клик:кнопка-лобби-назад');
      слушателиКнопкиЛобби.slice().forEach(ф => ф());
    }
  };

  // «Кнопка-мой-счёт» — стоит только на index.html.
  const слушателиКнопкиМойСчёт = [];
  const кнопкаМойСчёт = {
    addEventListener(тип, ф) { слушателиКнопкиМойСчёт.push(ф); },
    click() {
      журнал.push('клик:кнопка-мой-счёт');
      слушателиКнопкиМойСчёт.slice().forEach(ф => ф());
    }
  };

  const документ = {
    querySelectorAll(селектор) {
      return селектор === '.нижние-вкладки[data-вкладки]' ? [navРейтинг] : [];
    },
    getElementById(id) {
      if (id === 'экран-рейтинга-игроков') return узелЭкранаРейтинга;
      if (id === 'кнопка-лобби-назад') return опции.естьКнопкаЛобби !== false ? кнопкаЛоббиНазад : null;
      if (id === 'кнопка-мой-счёт') return опции.естьКнопкаМойСчёт !== false ? кнопкаМойСчёт : null;
      return null;
    }
  };

  const окно = {
    location: { pathname: опции.путьСтраницы || '/' },
    кВыборуИгры() { журнал.push('кВыборуИгры'); }
  };
  if (опции.естьЭкранРейтинга !== false) {
    окно.ЭкранРейтинга = {
      открытьСчёт(игра) { журнал.push('открытьСчёт:' + игра); }
    };
    if (опции.сЗакрытьПанели !== false) {
      окно.ЭкранРейтинга.закрытьПанели = function () {
        закрытьПанелиВызовов++;
        журнал.push('закрытьПанели');
      };
    }
  }
  окно.document = документ;

  const песочница = {
    module: { exports: {} },
    console: { log() {}, warn() {}, error() {} },
    window: окно,
    document: документ
  };
  песочница.exports = песочница.module.exports;
  vm.createContext(песочница);
  vm.runInContext(исходник, песочница, { filename: 'js/нижние-вкладки.js (проверка шторок рейтинга)' });

  function нажатьДействие(имяДействия) {
    if (!действия[имяДействия]) return false;
    действия[имяДействия].click();
    return true;
  }

  return {
    нажатьДействие: нажатьДействие,
    журнал: журнал,
    закрытьПанелиВызовов: function () { return закрытьПанелиВызовов; }
  };
}

/** Индекс первого вхождения метки в журнале, или -1 (метки не было вовсе). */
function индекс(журнал, метка) { return журнал.indexOf(метка); }

/**
 * Весь набор проверок одним прогоном по указанному пути к файлу.
 * Возвращает { строки, провалов } — печать и код выхода решает вызывающий.
 */
function прогнатьПроверки(путь) {
  const строки = [];
  let провалов = 0;
  function проверка(имя, условие, подробности) {
    if (условие) {
      строки.push('OK    ' + имя);
    } else {
      провалов++;
      строки.push('ПЛОХО ' + имя + (подробности ? ' — ' + подробности : ''));
    }
  }

  // --- (а) «к-играм-рейтинг», обычный вход (кнопка-лобби-назад есть) ---
  {
    const в = поднятьНижниеВкладки(путь, {});
    const нашлось = в.нажатьДействие('к-играм-рейтинг');
    проверка('к-играм-рейтинг: действие найдено в разметке (не ноль)', нашлось === true);
    проверка('к-играм-рейтинг: закрытьПанели вызвана ровно один раз', в.закрытьПанелиВызовов() === 1,
      'вызовов: ' + в.закрытьПанелиВызовов());
    const иЗакрытьПанели = индекс(в.журнал, 'закрытьПанели');
    const иСпрятатьЭкран = индекс(в.журнал, 'спрятатьЭкран:экран-рейтинга-игроков');
    const иКликЛобби = индекс(в.журнал, 'клик:кнопка-лобби-назад');
    проверка('к-играм-рейтинг: закрытьПанели вызвана РАНЬШЕ, чем спрятан экран рейтинга',
      иЗакрытьПанели !== -1 && иСпрятатьЭкран !== -1 && иЗакрытьПанели < иСпрятатьЭкран,
      'журнал: ' + в.журнал.join(' → '));
    проверка('к-играм-рейтинг: закрытьПанели вызвана РАНЬШЕ клика по кнопке-лобби-назад',
      иЗакрытьПанели !== -1 && иКликЛобби !== -1 && иЗакрытьПанели < иКликЛобби,
      'журнал: ' + в.журнал.join(' → '));
  }

  // --- (а, запасной вход) «к-играм-рейтинг» на index.html — нет кнопки-
  //     лобби-назад, дверь — window.кВыборуИгры() ---
  {
    const в = поднятьНижниеВкладки(путь, { естьКнопкаЛобби: false });
    в.нажатьДействие('к-играм-рейтинг');
    const иЗакрытьПанели = индекс(в.журнал, 'закрытьПанели');
    const иКВыборуИгры = индекс(в.журнал, 'кВыборуИгры');
    проверка('к-играм-рейтинг (на index.html, без кнопки-лобби-назад): закрытьПанели вызвана РАНЬШЕ window.кВыборуИгры',
      иЗакрытьПанели !== -1 && иКВыборуИгры !== -1 && иЗакрытьПанели < иКВыборуИгры,
      'журнал: ' + в.журнал.join(' → '));
  }

  // --- (б) «мой-счёт-рейтинг» на index.html (кнопка-мой-счёт есть) ---
  {
    const в = поднятьНижниеВкладки(путь, {});
    const нашлось = в.нажатьДействие('мой-счёт-рейтинг');
    проверка('мой-счёт-рейтинг: действие найдено в разметке (не ноль)', нашлось === true);
    проверка('мой-счёт-рейтинг: закрытьПанели вызвана ровно один раз', в.закрытьПанелиВызовов() === 1,
      'вызовов: ' + в.закрытьПанелиВызовов());
    const иЗакрытьПанели = индекс(в.журнал, 'закрытьПанели');
    const иКликМойСчёт = индекс(в.журнал, 'клик:кнопка-мой-счёт');
    проверка('мой-счёт-рейтинг: закрытьПанели вызвана РАНЬШЕ клика по кнопке-мой-счёт',
      иЗакрытьПанели !== -1 && иКликМойСчёт !== -1 && иЗакрытьПанели < иКликМойСчёт,
      'журнал: ' + в.журнал.join(' → '));
  }

  // --- (б, запасной вход) «мой-счёт-рейтинг» на шашки.html — нет кнопки-
  //     мой-счёт, игру узнаёт по адресу, зовёт ЭкранРейтинга.открытьСчёт ---
  {
    const в = поднятьНижниеВкладки(путь, { естьКнопкаМойСчёт: false, путьСтраницы: '/шашки.html' });
    в.нажатьДействие('мой-счёт-рейтинг');
    const иЗакрытьПанели = индекс(в.журнал, 'закрытьПанели');
    const иОткрытьСчёт = индекс(в.журнал, 'открытьСчёт:шашки');
    проверка('мой-счёт-рейтинг (на шашки.html, без кнопки-мой-счёт): закрытьПанели вызвана РАНЬШЕ ЭкранРейтинга.открытьСчёт',
      иЗакрытьПанели !== -1 && иОткрытьСчёт !== -1 && иЗакрытьПанели < иОткрытьСчёт,
      'журнал: ' + в.журнал.join(' → '));
  }

  // --- (в) СТАРЫЙ рейтинг-экран без закрытьПанели: работает без исключения,
  //     экран прячется/дверь нажимается как раньше ---
  {
    let упало = false;
    let в;
    try {
      в = поднятьНижниеВкладки(путь, { сЗакрытьПанели: false });
      в.нажатьДействие('к-играм-рейтинг');
    } catch (e) { упало = true; }
    проверка('к-играм-рейтинг (старый ЭкранРейтинга без закрытьПанели): не бросает исключение', !упало);
    проверка('к-играм-рейтинг (старый ЭкранРейтинга без закрытьПанели): экран рейтинга всё равно прячется',
      !упало && индекс(в.журнал, 'спрятатьЭкран:экран-рейтинга-игроков') !== -1);
    проверка('к-играм-рейтинг (старый ЭкранРейтинга без закрытьПанели): дверь всё равно нажата',
      !упало && индекс(в.журнал, 'клик:кнопка-лобби-назад') !== -1);
  }
  {
    let упало = false;
    let в;
    try {
      в = поднятьНижниеВкладки(путь, { сЗакрытьПанели: false });
      в.нажатьДействие('мой-счёт-рейтинг');
    } catch (e) { упало = true; }
    проверка('мой-счёт-рейтинг (старый ЭкранРейтинга без закрытьПанели): не бросает исключение', !упало);
    проверка('мой-счёт-рейтинг (старый ЭкранРейтинга без закрытьПанели): дверь всё равно нажата',
      !упало && индекс(в.журнал, 'клик:кнопка-мой-счёт') !== -1);
  }

  // --- (г) window.ЭкранРейтинга нет вовсе (модуль рейтинга не подключён) ---
  {
    let упало = false;
    let в;
    try {
      в = поднятьНижниеВкладки(путь, { естьЭкранРейтинга: false });
      в.нажатьДействие('к-играм-рейтинг');
    } catch (e) { упало = true; }
    проверка('к-играм-рейтинг (window.ЭкранРейтинга нет вовсе): не бросает исключение', !упало);
    проверка('к-играм-рейтинг (window.ЭкранРейтинга нет вовсе): экран рейтинга всё равно прячется',
      !упало && индекс(в.журнал, 'спрятатьЭкран:экран-рейтинга-игроков') !== -1);
  }
  {
    let упало = false;
    let в;
    try {
      в = поднятьНижниеВкладки(путь, { естьЭкранРейтинга: false });
      в.нажатьДействие('мой-счёт-рейтинг');
    } catch (e) { упало = true; }
    проверка('мой-счёт-рейтинг (window.ЭкранРейтинга нет вовсе): не бросает исключение', !упало);
    проверка('мой-счёт-рейтинг (window.ЭкранРейтинга нет вовсе): дверь всё равно нажата',
      !упало && индекс(в.журнал, 'клик:кнопка-мой-счёт') !== -1);
  }

  return { строки, провалов };
}

if (!сломать) {
  console.log('=== Проверка: нижние вкладки закрывают шторки рейтинга (обычный прогон) ===');
  const { строки, провалов } = прогнатьПроверки(ПУТЬ_НАСТОЯЩИЙ);
  строки.forEach(с => console.log(с));
  console.log('');
  console.log('Итого проверок: ' + строки.length + ', провалов: ' + провалов);
  process.exitCode = провалов ? 1 : 0;
} else {
  /* --- ЛОМАЮЩИЙ ПРОГОН --сломать ---
     Портим КОПИЮ во временной папке (os.tmpdir()) — убираем из неё оба
     вызова закрытьШторкиРейтинга(). Настоящий файл проекта не трогаем
     ни на секунду. Точные строки не нашлись — приём порчи устарел,
     падаем явно кодом 1, а не тихо проходим «зелёным». */
  console.log('=== Проверка: нижние вкладки закрывают шторки рейтинга (ЛОМАЮЩИЙ прогон --сломать) ===');

  const исходникНастоящий = fs.readFileSync(ПУТЬ_НАСТОЯЩИЙ, 'utf8');
  const БЫЛО_ИГРЫ = "'к-играм-рейтинг': function () {\r\n      закрытьШторкиРейтинга();\r\n";
  const БЫЛО_СЧЁТ = "'мой-счёт-рейтинг': function () {\r\n      закрытьШторкиРейтинга();\r\n";
  if (исходникНастоящий.indexOf(БЫЛО_ИГРЫ) === -1 || исходникНастоящий.indexOf(БЫЛО_СЧЁТ) === -1) {
    console.log('ПЛОХО: приём порчи устарел — точные строки вызова закрытьШторкиРейтинга() не найдены в js/нижние-вкладки.js');
    process.exit(1);
  }
  const испорченныйИсходник = исходникНастоящий
    .split(БЫЛО_ИГРЫ).join("'к-играм-рейтинг': function () {\r\n")
    .split(БЫЛО_СЧЁТ).join("'мой-счёт-рейтинг': function () {\r\n");

  const временныйПуть = path.join(os.tmpdir(), 'нижние-вкладки-испорченный-' + Date.now() + '.js');
  fs.writeFileSync(временныйПуть, испорченныйИсходник, 'utf8');

  try {
    const { строки } = прогнатьПроверки(временныйПуть);
    строки.forEach(с => console.log(с));

    const поймалиА = строки.some(с => с.indexOf('ПЛОХО') === 0 && с.indexOf('к-играм-рейтинг: закрытьПанели вызвана РАНЬШЕ') !== -1);
    const поймалиБ = строки.some(с => с.indexOf('ПЛОХО') === 0 && с.indexOf('мой-счёт-рейтинг: закрытьПанели вызвана РАНЬШЕ') !== -1);

    console.log('');
    if (поймалиА && поймалиБ) {
      console.log('ИТОГ ЛОМАЮЩЕГО ПРОГОНА: порча поймана — пункты (а) и (б) покраснели, как и требовалось');
      process.exitCode = 0;
    } else {
      console.log('ИТОГ ЛОМАЮЩЕГО ПРОГОНА: ...СЛЕПАЯ... — порча не поймана (а: ' + поймалиА + ', б: ' + поймалиБ + ')');
      process.exitCode = 1;
    }
  } finally {
    fs.unlinkSync(временныйПуть);
  }
}
