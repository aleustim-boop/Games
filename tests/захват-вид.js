/* Сервер: сперва ищет файл в папке-копии (если дана), потом в проекте. */
function поднятьСервер(копия) {
  const сервер = http.createServer((запрос, ответ) => {
    let путь = '/';
    try { путь = decodeURIComponent(запрос.url.split('?')[0]); } catch (_) { /* как есть */ }
    if (путь === '/') путь = '/index.html';
    const варианты = [];
    if (копия) варианты.push([копия, path.join(копия, путь)]);
    варианты.push([ПРОЕКТ, path.join(ПРОЕКТ, путь)]);
    for (const [корень, файл] of варианты) {
      if (!файл.startsWith(корень)) continue;
      try {
        if (fs.statSync(файл).isFile()) {
          ответ.writeHead(200, { 'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'application/octet-stream' });
          ответ.end(fs.readFileSync(файл));
          return;
        }
      } catch (_) { /* пробуем дальше */ }
    }
    ответ.writeHead(404); ответ.end('нет такого файла');
  });
  return new Promise(готово => сервер.listen(0, '127.0.0.1', () => готово(сервер)));
}

/* Порча — только в КОПИИ во временной папке. */
function подготовитьКопию(режим) {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-вид-сломан-'));
  if (режим === 'эффекты') {
    // Копия js/захват-экран.js: шаги «стрелка» и «вспышка» пропускаются — на холсте нет ни стрелок, ни вспышек.
    const исходник = fs.readFileSync(path.join(ПРОЕКТ, 'js', 'захват-экран.js'), 'utf8');
    const якорь = 'function сделатьШаг(шаг) {';
    if (исходник.indexOf(якорь) === -1) throw new Error('--сломать-эффекты: в js/захват-экран.js не нашлась функция сделатьШаг (якорь не найден — провал)');
    fs.mkdirSync(path.join(папка, 'js'), { recursive: true });
    fs.writeFileSync(path.join(папка, 'js', 'захват-экран.js'), исходник.replace(якорь, якорь + " if (шаг.вид === 'стрелка' || шаг.вид === 'вспышка') return;"));
  } else if (режим === 'размер') {
    // Копия js/захват-экран.js: вызов слушатьРазмер() убран — окно меняет размер, а карта и шайбы не пересчитываются.
    const исходник = fs.readFileSync(path.join(ПРОЕКТ, 'js', 'захват-экран.js'), 'utf8');
    const вызов = '\n  слушатьРазмер();\n';
    if (исходник.split(вызов).length !== 2) throw new Error('--сломать-размер: в js/захват-экран.js вызов слушатьРазмер() найден не один раз (якорь не найден — провал)');
    fs.mkdirSync(path.join(папка, 'js'), { recursive: true });
    fs.writeFileSync(path.join(папка, 'js', 'захват-экран.js'), исходник.replace(вызов, '\n  /* слушатьРазмер(); — отключено порчей */\n'));
  } else if (режим === 'место' || режим === 'холст' || режим === 'пластина' || режим === 'пилюля') {
    const css = fs.readFileSync(path.join(ПРОЕКТ, 'style-захват.css'), 'utf8');
    const порчи = {
      // Слой шайб со сдвигом от угла карты, как будто «карта в узле по центру» не учтена.
      место: ['position: absolute; left: calc(var(--карта-x, 0) * 1px); top: calc(var(--карта-y, 0) * 1px);',
        'position: absolute; left: calc(var(--карта-x, 0) * 1px + 24px); top: calc(var(--карта-y, 0) * 1px + 70px);'],
      // Холст сжат и прижат вниз: рисунок съезжает относительно слоя (ошибка до правки Г2б).
      холст: ['.захват-холст { position: absolute; inset: 0; display: block; width: 100%; height: 100%; }',
        '.захват-холст { position: absolute; inset: 0; display: block; width: 100%; height: 100%; object-fit: contain; object-position: 50% 100%; transform: translateY(70px) scale(0.9); }'],
      пластина: ['position: absolute; left: -1px; right: -1px; bottom: calc(100% + 7px); z-index: 3;',
        'position: absolute; left: -1px; right: -1px; bottom: 0; z-index: 3;'],
      пилюля: ['transform: translate(-50%, -100%); margin-top: -1px;', 'transform: translate(-50%, -100%) translateX(-2000px); margin-top: -1px;']
    };
    const [было, стало] = порчи[режим];
    const испорчен = css.replace(было, () => стало);
    if (испорчен === css) throw new Error('--сломать-' + режим + ': в style-захват.css не нашлось место порчи (якорь не найден — провал)');
    fs.writeFileSync(path.join(папка, 'style-захват.css'), испорчен);
  } else if (режим === 'слой') {
    const html = fs.readFileSync(path.join(ПРОЕКТ, 'захват.html'), 'utf8');
    const узел = '<div id="захват-слой" class="захват-слой"></div>';
    if (html.indexOf(узел) === -1) throw new Error('--сломать: в захват.html не нашёлся слой шайб #захват-слой');
    fs.writeFileSync(path.join(папка, 'захват.html'), html.replace(узел, ''));
  } else {
    const css = fs.readFileSync(path.join(ПРОЕКТ, 'style-захват.css'), 'utf8');
    const испорчен = css.replace('background-image: url("img/захват/шайбы.webp?v=1");', 'background-image: none;');
    if (испорчен === css) throw new Error('--сломать-фон: в style-захват.css не нашёлся фон шайб');
    fs.writeFileSync(path.join(папка, 'style-захват.css'), испорчен);
  }
  return папка;
}

