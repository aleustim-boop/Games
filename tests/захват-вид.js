/* Новая страница: подделка Telegram, «не новичок», слушатели консоли и сети. */
async function открыть(браузер, порт, ш, в) {
  const контекст = await браузер.newContext({ viewport: { width: ш, height: в } });
  const страница = await контекст.newPage();
  await подготовитьПодделку(страница, {});
  const сост = { ошибки: [], сбои: [], картинки: [], фаза: 'полный', цвета: new Set() };
  страница.on('console', с => {
    const адрес = с.location().url || '';
    if ((с.type() === 'error') && адрес.indexOf('telegram-web-app.js') === -1) сост.ошибки.push(с.text() + ' ' + адрес);
  });
  страница.on('pageerror', е => сост.ошибки.push('необработанная ошибка: ' + е.message));
  страница.on('requestfailed', з => { if (з.url().indexOf('telegram-web-app.js') === -1) сост.сбои.push('сбой ' + з.url()); });
  страница.on('response', о => {
    const адрес = decodeURIComponent(о.url());
    if (о.status() >= 400) сост.сбои.push(о.status() + ' ' + адрес);
    if (адрес.indexOf('/img/захват/') !== -1) сост.картинки.push({ имя: адрес.split('/img/захват/')[1].split('?')[0], код: о.status(), фаза: сост.фаза });
  });
  await страница.addInitScript(() => { try { localStorage.setItem('zahvat-learned', '1'); } catch (_) { /* пусто */ } });
  // Ловец: считает, что и каким листом рисуется на холсте. Кадр = все drawImage одного вызова рисования.
  // Когда ждём нужный кадр («стрелки» или «вспышка») и он нарисован, холст замораживается (чтобы снимок
  // успел снять именно его) до явной разморозки.
  await страница.addInitScript(() => {
    const П = CanvasRenderingContext2D.prototype;
    const Л = window.__ловец = { замок: false, ждём: null, поймано: null, последний: null };
    let пачка = null;
    const подходит = п => (Л.ждём === 'стрелки' ? п.сильных > 0 : Л.ждём === 'вспышка' ? п.кадры.some(к => к === 2 || к === 3) : false);
    ['clearRect', 'fillRect', 'putImageData', 'fill', 'stroke'].forEach(имя => {
      const о = П[имя]; if (!о) return;
      П[имя] = function () { if (Л.замок) return undefined; return о.apply(this, arguments); };
    });
    const ориг = П.drawImage;
    П.drawImage = function (img) {
      if (Л.замок) return undefined;
      if (!пачка) {
        пачка = { стрелок: 0, сильных: 0, кадры: [] };
        setTimeout(() => {
          const п = пачка; пачка = null; Л.последний = п;
          if (Л.ждём && !Л.поймано && подходит(п)) { Л.поймано = п; Л.замок = true; }
        }, 0);
      }
      let имя = '';
      try { имя = decodeURIComponent((img && img.src) || ''); } catch (_) { имя = ''; }
      if (/стрелки-/.test(имя)) { пачка.стрелок++; if (this.globalAlpha >= 0.7) пачка.сильных++; }
      if (/вспышка-кадры/.test(имя)) пачка.кадры.push(Math.round(arguments[1] / 256));
      return ориг.apply(this, arguments);
    };
  });
  await страница.goto('http://127.0.0.1:' + порт + '/захват.html', { waitUntil: 'load' });
  await страница.waitForTimeout(800);
  return { контекст, страница, сост };
}

