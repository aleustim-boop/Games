/* «Смена размера»: партия открыта при 390×844, окно меняется на 430×640 и потом на 360×740. После каждой смены
   все шайбы стоят на сотах своего цвета, а касание центра своей шайбы ставит войско в эту область (пилюля «+N»
   этой области растёт на 1). Ноль шайб — провал. Снимок на 430 — в папку снимков. */
async function проверитьСменуРазмера(браузер, порт) {
  const карта = { имя: 'остров', игроков: 3 };
  console.log('\n=== Смена размера: 390×844 → 430×640 → 360×740 ===');
  const { контекст, страница, сост } = await открыть(браузер, порт, 390, 844);
  try {
    await страница.click('#захват-боты');
    await страница.waitForTimeout(300);
    await страница.click('#захват-выбор-число [data-значение="' + карта.игроков + '"]');
    await страница.click('#захват-начать');
    await страница.waitForTimeout(1200);
    const цв = await узнатьЦвета(страница);
    проверить(!!цв.я, 'смена размера: стол открыт, цвет человека «' + цв.я + '»');
    await проверитьШайбуВСоте(страница, 'смена размера, до смены 390×844', карта.имя, false);
    for (const [ш, в] of [[430, 640], [360, 740]]) {
      const метка = 'смена размера → ' + ш + '×' + в;
      await страница.setViewportSize({ width: ш, height: в });
      await страница.waitForTimeout(900);
      await проверитьШайбы(страница, метка, карта.игроков);
      await проверитьШайбуВСоте(страница, метка, карта.имя, false);
      // Касание центра своей шайбы (по её настоящему месту после смены размера) ставит войско в эту область.
      const цель = await страница.evaluate(я => {
        const шайбы = Array.from(document.querySelectorAll('.захват-шайба--' + я));
        if (!шайбы.length) return null;
        const у = шайбы[0], п = у.getBoundingClientRect();
        const обл = у.getAttribute('data-область');
        const пил = Array.from(document.querySelectorAll('.захват-пилюля[data-область="' + обл + '"]'))[0];
        return { x: п.left + п.width / 2, y: п.top + п.height / 2, область: обл, было: пил ? parseInt((пил.textContent || '').replace(/\D/g, ''), 10) || 0 : 0 };
      }, цв.я);
      проверить(!!цель, метка + ': найдена своя шайба для касания');
      if (!цель) continue;
      await страница.mouse.click(цель.x, цель.y);
      await страница.waitForTimeout(400);
      const стало = await страница.evaluate(обл => {
        const пил = Array.from(document.querySelectorAll('.захват-пилюля[data-область="' + обл + '"]'))[0];
        return пил ? parseInt((пил.textContent || '').replace(/\D/g, ''), 10) || 0 : 0;
      }, цель.область);
      проверить(стало === цель.было + 1, метка + ': касание центра своей шайбы (область ' + цель.область + ') поставило войско: «+N» было ' + цель.было + ', стало ' + стало);
      if (ш === 430) {
        const файл = 'смена-размера-430.png';
        await страница.screenshot({ path: path.join(ПАПКА, файл) });
        сниматьсяФайлы.push(файл);
      }
    }
    проверить(сост.ошибки.length === 0, 'смена размера: консоль без ошибок' + (сост.ошибки.length ? ': ' + сост.ошибки.slice(0, 3).join(' | ') : ''));
  } catch (е) {
    проверить(false, 'смена размера: проверка упала: ' + String(е.message || е).split('\n')[0]);
  }
  await контекст.close();
}

/* Замер раскрытия при замедлении процессора ×4. */
async function замерить(браузер, порт, карта, лёгкий) {
  const [ш, в] = [390, 844];
  const метка = 'замер ' + карта.имя + (лёгкий ? ' лёгкий' : ' полный');
  const { контекст, страница } = await открыть(браузер, порт, ш, в);
  await страница.click('#захват-боты');
  await страница.waitForTimeout(300);
  await страница.click('#захват-выбор-число [data-значение="' + карта.игроков + '"]');
  await страница.click('#захват-начать');
  await страница.waitForTimeout(1200);
  if (лёгкий) {
    await открытьЛист(страница);
    await страница.waitForTimeout(300);
    const подпись = await страница.evaluate(() => (document.getElementById('кнопка-лист-игры-оформление') || {}).textContent || '');
    if (/Полные/.test(подпись)) await страница.click('#кнопка-лист-игры-оформление');
    await страница.waitForTimeout(800);
    await страница.keyboard.press('Escape');
    await страница.waitForTimeout(300);
  }
  const сессия = await контекст.newCDPSession(страница);
  await сессия.send('Emulation.setCPUThrottlingRate', { rate: 4 });
  const р1 = await страница.evaluate(() => (document.getElementById('захват-раунд').textContent || '').trim());
  await страница.evaluate(р1 => {
    window.__кадры = []; window.__конец = false; window.__т0 = performance.now(); window.__т1 = null;
    let последний;
    const цикл = т => { if (последний !== undefined) window.__кадры.push(т - последний); последний = т; if (!window.__конец) requestAnimationFrame(цикл); };
    requestAnimationFrame(цикл);
    new MutationObserver(() => { if (window.__т1 === null && (document.getElementById('захват-раунд').textContent || '').trim() !== р1) { window.__т1 = performance.now(); window.__конец = true; } })
      .observe(document.getElementById('захват-раунд'), { childList: true, characterData: true, subtree: true });
    document.addEventListener('click', е => { if (е.target.closest && е.target.closest('#захват-готово, #захват-остаток-да')) { window.__т0 = performance.now(); window.__кадры = []; } }, true);
  }, р1);
  await страница.click('#захват-готово');
  await страница.waitForTimeout(400);
  if (await страница.evaluate(() => { const у = document.getElementById('захват-остаток'); return !!у && !у.classList.contains('скрыт'); })) {
    await страница.click('#захват-остаток-да', { timeout: 4000 }).catch(() => {});
  }
  const дошло = await страница.waitForFunction(() => window.__т1 !== null, null, { timeout: 60000 }).then(() => true, () => false);
  const р = await страница.evaluate(() => ({ кадры: window.__кадры.slice(), общее: window.__т1 === null ? null : window.__т1 - window.__т0 }));
  await сессия.send('Emulation.setCPUThrottlingRate', { rate: 1 });
  await контекст.close();
  проверить(дошло && р.кадры.length > 10, метка + ': раскрытие дошло до нового раунда, кадров записано ' + р.кадры.length + (р1 ? ' (раунд «' + р1 + '»)' : ''));
  if (!р.кадры.length) return null;
  const сред = р.кадры.reduce((а, б) => а + б, 0) / р.кадры.length;
  const худший = Math.max.apply(null, р.кадры);
  const долгих = р.кадры.filter(к => к > 50).length;
  const итог = { метка, кадров: р.кадры.length, сред: Math.round(сред * 10) / 10, худший: Math.round(худший * 10) / 10, долгих, общее: р.общее === null ? null : Math.round(р.общее) };
  console.log('  ЗАМЕР ×4 — ' + метка + ': кадров ' + итог.кадров + ', средний ' + итог.сред + ' мс, худший ' + итог.худший + ' мс, дольше 50 мс: ' + итог.долгих + ', общее время ' + итог.общее + ' мс (по расписанию 8000)');
  return итог;
}

