'use strict';

/* Проверка броска заходной по сети. Свой сервер на 8799 (рабочий 8790
   не трогаем), карты раскладываются руками прямо в партии комнаты —
   так положение на столе точно то, какое нужно проверке.

   1. Гонка двоих живых: стол на троих, место ровно для одной карты, двое
      шлют бросок одновременно — принят ровно один, стол правильный,
      у проигравшего карта на месте.
   2. Отказы словами: защитнику, чужому подходу.
   3. Бот бросает заходную сам, через длинную паузу, а насос не умирает. */

const path = require('path');
const КОРЕНЬ = require('path').resolve(__dirname, '..');   // корень проекта — от этого файла, а не зашитый
const сервер = require(path.join(КОРЕНЬ, 'server/сервер.js'));
const комнаты = require(path.join(КОРЕНЬ, 'server/комнаты.js'));
const партии = require(path.join(КОРЕНЬ, 'server/партия-по-сети.js'));
const правила = require(path.join(КОРЕНЬ, 'js/game.js'));

const ПОРТ = 8799;
const АДРЕС = 'http://127.0.0.1:' + ПОРТ;

function стук(путь, тело) {
  return fetch(АДРЕС + путь, {
    method: 'POST', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(тело || {})
  }).then(function (о) { return о.json().then(function (д) { return { номер: о.status, данные: д }; }); });
}
const спать = function (мс) { return new Promise(function (f) { setTimeout(f, мс); }); };

let всёХорошо = true;
function проверить(что, правда) {
  console.log((правда ? '  ок   ' : '  БЕДА ') + что);
  if (!правда) всёХорошо = false;
}

const масти = Array.isArray(правила.МАСТИ) ? правила.МАСТИ : Object.keys(правила.МАСТИ);
const достоинства = Array.isArray(правила.ДОСТОИНСТВА) ? правила.ДОСТОИНСТВА : Object.keys(правила.ДОСТОИНСТВА);
function карта(имя, масть) { return { масть: масть, имя: имя }; }
const ШЕСТЬ = достоинства[0];

async function гонкаДвоих() {
  console.log('1. Гонка двоих живых');
  const а = await стук('/создать', { имя: 'Аня', мест: 3 });
  const б = await стук('/войти', { код: а.данные.код, имя: 'Боря' });
  const в = await стук('/войти', { код: а.данные.код, имя: 'Вася' });
  const код = а.данные.код;
  const начали = await стук('/ход', { код: код, пропуск: а.данные.пропуск, действие: 'начать' });
  проверить('стол на троих начался', начали.данные.принято === true);

  const комната = комнаты.найтиИгрока(код, а.данные.пропуск).комната;
  const партия = комната.партия;
  const пропуск = {};
  for (const п of [а.данные.пропуск, б.данные.пропуск, в.данные.пропуск]) {
    пропуск[комнаты.найтиИгрока(код, п).ктоЯ] = п;
  }
  const защитник = правила.защищается(партия);
  const атакующий = партия.атакует;
  const третий = партия.игроки.filter(function (м) { return м !== защитник && м !== атакующий; })[0];

  /* Раскладка: заходная шестёрка на столе, у защитника две карты — значит
     места хватит ровно на одну брошенную (неотбитых станет 2 = карт в руке). */
  партия.стол = [{ атака: карта(ШЕСТЬ, масти[0]), защита: null }];
  партия.руки[защитник] = [карта(достоинства[1], масти[1]), карта(достоинства[2], масти[1])];
  партия.руки[атакующий] = [карта(ШЕСТЬ, масти[1]), карта(достоинства[3], масти[2])];
  партия.руки[третий] = [карта(ШЕСТЬ, масти[2]), карта(достоинства[4], масти[2])];
  партия.пасы = [];
  партия.берёт = false;
  const подход = партия.подходов;

  проверить('в виде атакующего могуПодхватить = true',
    партии.видДляИгрока(партия, атакующий, {}).могуПодхватить === true);
  проверить('в виде защитника могуПодхватить = false',
    партии.видДляИгрока(партия, защитник, {}).могуПодхватить === false);

  console.log('2. Отказы словами');
  const защ = await стук('/ход', { код: код, пропуск: пропуск[защитник], действие: 'подхватить', карта: 0, подход: подход });
  проверить('защитнику нельзя: ' + защ.данные.причина,
    защ.данные.принято === false && /отбиваетесь/.test(защ.данные.причина || ''));
  const уехал = await стук('/ход', { код: код, пропуск: пропуск[третий], действие: 'подхватить', карта: 0, подход: подход + 1 });
  проверить('чужой подход: ' + уехал.данные.причина,
    уехал.данные.принято === false && /уехал/.test(уехал.данные.причина || ''));
  const безПодхода = await стук('/ход', { код: код, пропуск: пропуск[третий], действие: 'подхватить', карта: 0 });
  проверить('без номера подхода: ' + безПодхода.данные.причина, безПодхода.данные.принято === false);
  проверить('после отказов стол не изменился', партия.стол.length === 1);

  console.log('   гонка: двое шлют бросок одновременно');
  const итоги = await Promise.all([
    стук('/ход', { код: код, пропуск: пропуск[атакующий], действие: 'подхватить', карта: 0, подход: подход }),
    стук('/ход', { код: код, пропуск: пропуск[третий], действие: 'подхватить', карта: 0, подход: подход })
  ]);
  const принятых = итоги.filter(function (о) { return о.данные.принято === true; }).length;
  проверить('принят ровно один из двух', принятых === 1);
  проверить('стол — две шестёрки', партия.стол.length === 2 && партия.стол[1].атака.имя === ШЕСТЬ);
  const победитель = итоги[0].данные.принято ? атакующий : третий;
  const проигравший = победитель === атакующий ? третий : атакующий;
  const отказ = итоги[0].данные.принято ? итоги[1] : итоги[0];
  console.log('   победил ' + победитель + ', проигравшему сказано: ' + отказ.данные.причина);
  проверить('у победителя осталась 1 карта', партия.руки[победитель].length === 1);
  проверить('у проигравшего обе карты на месте, шестёрка первая',
    партия.руки[проигравший].length === 2 && партия.руки[проигравший][0].имя === ШЕСТЬ);
  проверить('проигравшему отказано словами', typeof отказ.данные.причина === 'string' && отказ.данные.причина.length > 5);

  const своё = await стук('/состояние', { код: код, пропуск: пропуск[победитель] });
  const чужое = await стук('/состояние', { код: код, пропуск: пропуск[защитник] });
  console.log('   рассказ себе: «' + своё.данные.состояние.событие + '», защитнику: «' + чужое.данные.состояние.событие + '»');
  проверить('себе: «Вы бросили <карта>»', /^Вы бросили \S+/.test(своё.данные.состояние.событие || ''));
  проверить('другому: «<имя> бросает <карта>»', /бросает \S+/.test(чужое.данные.состояние.событие || ''));
  проверить('в виде есть подходов', typeof своё.данные.состояние.подходов === 'number');

  for (const м of Object.keys(пропуск)) await стук('/выйти', { код: код, пропуск: пропуск[м] });
}

async function ботБросает() {
  console.log('3. Бот бросает заходную сам');
  const к = await стук('/создать', { имя: 'Аня', мест: 3 });
  const код = к.данные.код;
  await стук('/ход', { код: код, пропуск: к.данные.пропуск, действие: 'бот' });
  await стук('/ход', { код: код, пропуск: к.данные.пропуск, действие: 'бот' });
  const начали = await стук('/ход', { код: код, пропуск: к.данные.пропуск, действие: 'начать' });
  проверить('стол с двумя ботами начался', начали.данные.принято === true);

  const найдено = комнаты.найтиИгрока(код, к.данные.пропуск);
  const комната = найдено.комната;
  const аня = найдено.ктоЯ;
  const п = комната.партия;
  const всего = п.игроки.length;
  const яИндекс = п.игроки.indexOf(аня);
  // Аня защищается: нападает сосед перед ней, бросает сосед после неё.
  const местоАтаки = (яИндекс - 1 + всего) % всего;
  п.атакует = п.игроки[местоАтаки];
  п.местоАтаки = местоАтаки;
  п.пасы = [];
  п.берёт = false;
  const бросающий = п.игроки[(яИндекс + 1) % всего];
  проверить('Аня защищается', правила.защищается(п) === аня);

  const некозырная = масти.filter(function (м) { return м !== п.козырь; });
  п.стол = [{ атака: карта(ШЕСТЬ, некозырная[0]), защита: null }];
  // Очередь у защитника только когда на столе есть что отбивать — спрашиваем после раскладки.
  проверить('очередь у Ани (защита)', правила.ктоХодит(п) === аня);
  п.руки[аня] = [карта(достоинства[1], некозырная[1]), карта(достоинства[2], некозырная[1]),
                 карта(достоинства[3], некозырная[1]), карта(достоинства[4], некозырная[1])];
  п.руки[п.атакует] = [карта(достоинства[5], некозырная[0]), карта(достоинства[6], некозырная[0])];
  п.руки[бросающий] = [карта(ШЕСТЬ, некозырная[1]), карта(достоинства[5], некозырная[1])];

  const план = партии.ктоИзБотовПодхватит(п, function (имя) { return имя === аня ? null : 'средний'; });
  console.log('   план правил: ' + JSON.stringify(план));
  проверить('правила выбирают бросающего', план && план.кто === бросающий && план.карта === 0);

  /* Насос сейчас ждёт хода атакующего бота (таймер на 0,7 с, заведён при
     «начать»). Сработает — очередь окажется не его, и насос перепланирует:
     заведёт бросок через 3 с. Ждём с запасом. */
  const началось = Date.now();
  let бросил = false;
  while (Date.now() - началось < 6000) {
    await спать(200);
    if (п.стол.length === 2) { бросил = true; break; }
  }
  const прошло = Date.now() - началось;
  console.log('   стол стал из двух карт через ' + прошло + ' мс');
  проверить('бот бросил заходную сам', бросил && п.стол[1].атака.imя === undefined && п.стол[1].атака.имя === ШЕСТЬ);
  проверить('не раньше длинной паузы (≥ 3000 мс от перепланирования)', прошло >= 3000);
  проверить('у бросившего осталась 1 карта', п.руки[бросающий].length === 1);
  const вид = await стук('/состояние', { код: код, пропуск: к.данные.пропуск });
  console.log('   Аня видит: «' + вид.данные.состояние.событие + '»');
  проверить('Аня видит рассказ с картой', /бросает \S+/.test(вид.данные.состояние.событие || ''));
  проверить('у Ани могуПодхватить = false (она отбивается)', вид.данные.состояние.могуПодхватить === false);
  проверить('насос жив и не крутится впустую: план пуст, очередь у Ани',
    правила.ктоХодит(п) === аня && комната.планБота === null);

  await стук('/выйти', { код: код, пропуск: к.данные.пропуск });
}

сервер.запустить(ПОРТ, 2000);
гонкаДвоих().then(ботБросает).then(function () {
  console.log(всёХорошо ? 'ИТОГ: всё сошлось.' : 'ИТОГ: есть беды, смотри выше.');
}).catch(function (сбой) {
  всёХорошо = false;
  console.log('Проверка сорвалась: ' + (сбой && сбой.stack || сбой));
}).then(function () {
  process.exit(всёХорошо ? 0 : 1);
});
