/** Комната по коду и пропуску — прямо из модуля комнат сервера. */
function комнатаПо(код, пропуск) {
  const найдено = код && пропуск ? комнаты.найтиИгрока(код, пропуск) : null;
  return найдено ? найдено.комната : null;
}

/** Кто сидит за столом: людей, ботов, мест, номера людей, уровни ботов. */
function составСтола(комната) {
  const сидят = комната ? Object.values(комната.игроки).filter(Boolean) : [];
  const люди = сидят.filter(function (и) { return !и.этоБот; });
  const боты = сидят.filter(function (и) { return и.этоБот; });
  return {
    людей: люди.length,
    ботов: боты.length,
    мест: комната ? комната.мест : 0,
    номера: люди.map(function (и) { return и.телеграм; }),
    уровни: боты.map(function (б) { return б.уровень; })
  };
}

/** Отказ словами: ок false, причина — непустая строка, ни ключа, ни стола. */
function этоОтказСловами(тело) {
  return тело.ок === false && typeof тело.причина === 'string' && тело.причина.length > 0 &&
    !тело.ключОжидания && !тело.код && тело.статус === undefined;
}

