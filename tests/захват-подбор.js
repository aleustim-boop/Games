/** (в) Чтение файла: «захват» в обоих списках подбора. */
function случайФайл() {
  const текст = fs.readFileSync(path.join(ПАПКА, 'server', 'сервер.js'), 'utf8');

  const списки = текст.match(/const ИГРЫ_ПОДБОРА = \[([^\]]*)\]/g) || [];
  проверить(списки.length === 1, '(в) объявление ИГРЫ_ПОДБОРА найдено ровно один раз (нашлось: ' + списки.length + ')');
  const список = списки.length === 1 ? списки[0] : '';
  проверить(список.indexOf("'захват'") !== -1, '(в) «захват» есть в ИГРЫ_ПОДБОРА: ' + список.slice(0, 160));

  const уровни = текст.match(/const УРОВЕНЬ_БОТА_ОТ_ПОДБОРА = \{[^}]*\}/g) || [];
  проверить(уровни.length === 1, '(в) объявление УРОВЕНЬ_БОТА_ОТ_ПОДБОРА найдено ровно один раз (нашлось: ' + уровни.length + ')');
  const блок = уровни.length === 1 ? уровни[0] : '';
  проверить(/'захват':\s*'обычный'/.test(блок), "(в) в УРОВЕНЬ_БОТА_ОТ_ПОДБОРА есть 'захват': 'обычный'");
}

