/** Кусок с переводами строк того же вида, что в файле (файлы бывают в CRLF). */
function какВФайле(текст, кусок) {
  return текст.indexOf('\r\n') !== -1 ? кусок.split('\n').join('\r\n') : кусок;
}

function сколькоРаз(текст, кусок) {
  return текст.split(какВФайле(текст, кусок)).length - 1;
}

