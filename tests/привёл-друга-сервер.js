function портСвободен(порт) {
  return new Promise(function (готово) {
    const проба = net.createServer();
    проба.once('error', function () { готово(false); });
    проба.once('listening', function () { проба.close(function () { готово(true); }); });
    проба.listen(порт, ХОСТ);
  });
}

function убратьСвоё() {
  try { fs.rmSync(ПАПКА_ДАННЫХ, { recursive: true, force: true }); } catch (с) { /* временная папка — не беда */ }
  if (КОПИЯ) {
    try { fs.rmSync(КОПИЯ, { recursive: true, force: true }); } catch (с) { /* не беда */ }
  }
}

