function сделатьКопиюДляПорчи() {
  if (!ПАПКА_ЛОМАТЬ || !path.isAbsolute(ПАПКА_ЛОМАТЬ) || !fs.existsSync(ПАПКА_ЛОМАТЬ)) {
    console.log('ЛОМАЮЩИЙ ЗАПУСК НЕ СОСТОЯЛСЯ: после --сломать нужна существующая папка (полный путь).');
    process.exit(2);
  }
  const откудаПроект = path.resolve(КОРЕНЬ).toLowerCase() + path.sep;
  if ((path.resolve(ПАПКА_ЛОМАТЬ).toLowerCase() + path.sep).indexOf(откудаПроект) === 0) {
    console.log('ЛОМАЮЩИЙ ЗАПУСК НЕ СОСТОЯЛСЯ: папка для копии лежит внутри проекта — нужна папка вне его.');
    process.exit(2);
  }
  const врем = fs.mkdtempSync(path.join(ПАПКА_ЛОМАТЬ, 'привёл-друга-сломано-'));
  const данныеПроекта = path.join(КОРЕНЬ, 'server', 'данные');
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(врем, 'server'), {
    recursive: true,
    filter: function (откуда) { return откуда !== данныеПроекта && !откуда.startsWith(данныеПроекта + path.sep); }
  });
  require('./пути-проекта.js').скопироватьКод(КОРЕНЬ, врем, 'js');
  const файл = path.join(врем, 'server', 'сервер.js');
  const текст = fs.readFileSync(файл, 'utf8');
  const найдено = текст.split(ПОРЧА.было).length - 1;
  if (найдено !== 1) {
    console.log('ЛОМАЮЩИЙ ЗАПУСК НЕ СОСТОЯЛСЯ: в копии server/сервер.js место для порчи «' + ПОРЧА.что + '» найдено ' + найдено + ' раз, а нужно ровно 1.');
    fs.rmSync(врем, { recursive: true, force: true });
    process.exit(2);
  }
  fs.writeFileSync(файл, текст.split(ПОРЧА.было).join(ПОРЧА.стало), 'utf8');
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: в копии ' + врем + ' ' + ПОРЧА.что + ' — проверка обязана покраснеть ***');
  return врем;
}

