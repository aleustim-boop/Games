    const три = с.модуль.письмаНаСейчас(через(3));
    ждём(три.length === 1 && три[0].вид === '3дня' && три[0].номер === ГРОМКИЙ + 11, 'тишина ровно 3 дня: ждали одно «3дня», вышло «' + виды(три) + '»');
