function печатьПровалов(результат) {
  результат.провалы.forEach(function (с) { console.log('  ПРОВАЛ: ' + с); });
}

/** Дочерний процесс node в чужом поясе машины. */
function вПоясе(пояс, аргументы) {
  const итог = spawnSync(process.execPath, [__filename].concat(аргументы), {
    env: Object.assign({}, process.env, { TZ: пояс }),
    encoding: 'utf8'
  });
  const вывод = итог.stdout || '';
  const смещение = вывод.split('\n').filter(function (с) { return с.indexOf('СМЕЩЕНИЕ ') === 0; }).pop();
  return {
    код: итог.status,
    смещение: смещение ? Number(смещение.slice('СМЕЩЕНИЕ '.length)) : null,
    провалов: (вывод.match(/ПРОВАЛ:/g) || []).length,
    вывод: вывод + (итог.stderr || '')
  };
}

async function главное() {
  const аргумент = process.argv[2] || '';
  const смещениеЗдесь = new Date(Date.UTC(2026, 9, 5, 12, 0)).getTimezoneOffset();

  if (аргумент === '--внутри' || аргумент.indexOf('--сломать-') === 0 || аргумент.indexOf('--модуль=') === 0) {
    let модуль = НАСТОЯЩИЙ_МОДУЛЬ;
    let пометка = '';
    if (аргумент.indexOf('--сломать-') === 0) {
      const имя = аргумент.slice('--сломать-'.length);
      if (!ПОРЧИ[имя]) { console.log('Нет такой порчи: ' + имя); process.exit(2); }
      модуль = сделатьПорченую(имя);
      пометка = ' (порча «' + имя + '»: красное и нужно)';
    } else if (аргумент.indexOf('--модуль=') === 0) {
      модуль = path.resolve(аргумент.slice('--модуль='.length));
      if (!fs.existsSync(модуль)) { console.log('Нет такого файла: ' + модуль); process.exit(2); }
      пометка = ' (модуль: ' + модуль + ')';
    }
    const итог = await прогон(модуль);
    печатьПровалов(итог);
    console.log('СМЕЩЕНИЕ ' + смещениеЗдесь);
    console.log('Итого проверок: ' + итог.всего + ', провалов: ' + итог.провалы.length + пометка);
    process.exit(итог.провалы.length ? 1 : 0);
  }

  const настоящий = await прогон(НАСТОЯЩИЙ_МОДУЛЬ);
  печатьПровалов(настоящий);
  let всего = настоящий.всего;
  let провалов = настоящий.провалы.length;
  console.log('Прогон в поясе машины (смещение ' + смещениеЗдесь + ' мин): ' + (настоящий.провалы.length ? 'КРАСНЫЙ' : 'зелёный') + ', проверок ' + настоящий.всего);

  /* Тот же прогон в Asia/Tokyo. Пояс не сменился — сверка пустышка: краснеем. */
  const токио = вПоясе('Asia/Tokyo', ['--внутри']);
  всего += 2;
  if (токио.код !== 0) {
    провалов++;
    console.log('  ПРОВАЛ: прогон в поясе Asia/Tokyo упал:\n' + токио.вывод);
  }
  if (токио.смещение === null || токио.смещение === смещениеЗдесь || токио.смещение !== -540) {
    провалов++;
    console.log('  ПРОВАЛ: пояс в дочернем прогоне не Токио (смещение ' + токио.смещение + ', у нас ' + смещениеЗдесь + ', ждали -540) — проверка поясов ничего не доказывает');
  }
  console.log('Пояс Asia/Tokyo: смещение ' + токио.смещение + ' мин (ждали -540) — ' + (токио.код === 0 ? 'зелёный' : 'КРАСНЫЙ'));

  for (const имя of Object.keys(ПОРЧИ)) {
    let покраснела;
    let сколько;
    if (ПОРЧИ[имя].вПоясеТокио) {
      const д = вПоясе('Asia/Tokyo', ['--сломать-' + имя]);
      покраснела = д.код === 1 && д.провалов > 0 && д.смещение === -540;
      сколько = д.провалов;
    } else {
      const итог = await прогон(сделатьПорченую(имя));
      покраснела = итог.провалы.length > 0;
      сколько = итог.провалы.length;
    }
    console.log('Порча «' + имя + '»: ' + (покраснела ? 'покраснела (провалов: ' + сколько + ') — хорошо' : 'НЕ ПОКРАСНЕЛА — беда'));
    всего++;
    if (!покраснела) провалов++;
  }

  console.log('Итого проверок: ' + всего + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
}

главное().catch(function (беда) {
  console.log('Проверка упала: ' + (беда && беда.stack || беда));
  process.exit(1);
});
