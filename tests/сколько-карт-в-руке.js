/* =====================================================================
   Сколько карт реально скапливается в руке.

   Зачем это нужно. На узком или невысоком экране рука с большим числом
   карт превращается в сплошную полосу: от карты видно 6–14 точек, и
   пальцем в неё не попасть. Прежде чем считать это серьёзной бедой,
   надо честно ответить: а часто ли в живой партии рука вообще
   вырастает до 18, 26, 35 карт — или это выдуманный случай, до
   которого игрок никогда не доберётся?

   Скрипт играет много партий настоящими правилами из js/game.js
   и считает, до скольки карт доходила рука человека.

   Запуск:  node tests/сколько-карт-в-руке.js [сколько партий]
   ===================================================================== */

'use strict';

const игра = require(require('path').join(__dirname, '..', 'js', 'game.js'));

const ПАРТИЙ = Number(process.argv[2]) || 3000;
const ПРЕДЕЛ_ХОДОВ = 500;

// Свой генератор случайных чисел — чтобы результат можно было повторить
let зерно = 20260819;
Math.random = function () {
  зерно = (зерно * 1103515245 + 12345) % 2147483648;
  return зерно / 2147483648;
};

/* Играем обеими сторонами штатным ботом — это самый «нормальный» игрок,
   какой есть в игре. Если даже у него рука распухает, у живого человека
   тем более. */
function сыгратьПартию(сложность) {
  const партия = игра.создатьПартию(сложность);
  let максЧеловек = 6;
  let максБот = 6;
  let ходов = 0;

  while (!партия.завершена && ходов < ПРЕДЕЛ_ХОДОВ) {
    const чей = игра.ктоХодит(партия);
    const сделал = игра.ходБота(партия, чей, сложность);
    if (!сделал) {
      // Ход не сделан — завершаем подход, иначе партия встанет
      игра.завершитьПодход(партия);
    }
    if (партия.руки.человек.length > максЧеловек) максЧеловек = партия.руки.человек.length;
    if (партия.руки.бот.length > максБот) максБот = партия.руки.бот.length;
    ходов++;
  }
  return { максЧеловек: максЧеловек, максБот: максБот, доиграна: партия.завершена };
}

console.log('=== Насколько распухает рука за партию ===');
console.log('партий на уровень:', ПАРТИЙ);
console.log('');

const границы = [12, 15, 18, 20, 24, 26, 30, 35];

for (const сложность of ['лёгкий', 'обычный', 'сложный']) {
  let всегоМакс = 0;
  let сумма = 0;
  const сколькоРазДошло = {};
  for (const г of границы) сколькоРазДошло[г] = 0;
  let недоиграно = 0;

  for (let i = 0; i < ПАРТИЙ; i++) {
    const и = сыгратьПартию(сложность);
    if (!и.доиграна) недоиграно++;
    // Смотрим на обе руки: любая из них рисуется на экране крупной,
    // но нас интересует именно рука человека — её он тыкает пальцем.
    const м = и.максЧеловек;
    сумма += м;
    if (м > всегоМакс) всегоМакс = м;
    for (const г of границы) if (м >= г) сколькоРазДошло[г]++;
  }

  console.log('--- соперник «' + сложность + '» ---');
  console.log('  самая большая рука за все партии:', всегоМакс, 'карт');
  console.log('  в среднем максимум за партию:', (сумма / ПАРТИЙ).toFixed(1), 'карт');
  for (const г of границы) {
    const доля = (сколькоРазДошло[г] / ПАРТИЙ * 100).toFixed(1);
    console.log('  рука доходила до ' + String(г).padStart(2) + ' карт и больше: ' +
                String(сколькоРазДошло[г]).padStart(5) + ' партий из ' + ПАРТИЙ + '  (' + доля + '%)');
  }
  if (недоиграно) console.log('  ВНИМАНИЕ: не доиграно партий:', недоиграно);
  console.log('');
}

console.log('Вывод читать так: если проценты у 18 и 26 карт заметные —');
console.log('значит, «сплошная полоса вместо руки» будет попадаться живым игрокам,');
console.log('а не только в выдуманном стенде.');
