'use strict';

/* =====================================================================
   ЗАСТОЛЬЕ ДЛЯ РЕЙТИНГА: ПОЛЕ НАПАРНИК.

   Что проверяем. Функция застольеДляРейтинга (server/комнаты.js) добавляет
   поле напарник в результат для каждого игрока. Это поле содержит telegram-номер
   напарника в игре парами (2 на 2), или null в остальных случаях.

   Проверяем:
     — если комната.парами НЕ true → все результаты содержат напарник: null
     — если комната.парами === true, 4 места → напарники правильно спарены
       (0 и 2 — напарники, 1 и 3 — напарники, с правильными телеграм-номерами)
     — если комната.парами === true, но напарник уже вышел и был удалён
       из комната.игроки → для оставшегося должен быть напарник: null
       (не падение с ошибкой)

   Запуск:
       node tests/застолье-рейтинга-напарник.js
   ===================================================================== */

const path = require('path');
const комнаты = require(path.join(__dirname, '..', 'server', 'комнаты.js'));

let провалов = 0;
let проверок = 0;

function проверить(описание, условие) {
  проверок++;
  if (!условие) {
    console.log('  ✗ ' + описание);
    провалов++;
  } else {
    console.log('  ✓ ' + описание);
  }
}

/**
 * Создать mock-объект комнаты для тестирования застольеДляРейтинга.
 * параметры:
 *   - парами: true/false (нужно ли создавать игру парами)
 *   - мест: число мест за столом (по умолчанию 2)
 *   - игрокиДанные: массив объектов с полями телеграм, имя, этоБот, уровень
 */
function создатьМокКомнату(параметры) {
  параметры = параметры || {};
  const мест = параметры.мест || 2;
  const парами = параметры.парами || false;
  const игрокиДанные = параметры.игрокиДанные || [];

  // Имена мест за столом (как в game.js)
  const ИМЕНА_МЕСТ = ['человек', 'бот', 'бот-3', 'бот-4', 'бот-5', 'бот-6'];

  // Сформировать объект игроков
  const игроки = {};
  for (let i = 0; i < Math.min(мест, игрокиДанные.length); i++) {
    const имяМеста = ИМЕНА_МЕСТ[i];
    const данные = игрокиДанные[i];
    игроки[имяМеста] = {
      телеграм: данные.телеграм,
      имя: данные.имя,
      этоБот: данные.этоБот || false,
      уровень: данные.уровень || 'обычный'
    };
  }

  return {
    мест: мест,
    партия: {
      завершена: true,
      ничья: false,
      проигравшие: [],  // никто не проигрывал, все победили или ничья
      игроки: ИМЕНА_МЕСТ.slice(0, мест),  // список имён мест в порядке
      парами: парами
    },
    игроки: игроки,
    парами: парами,
    переводной: false,
    уровеньБотов: 'обычный'
  };
}


/**
 * ТЕСТ 1: Не парами — все напарники null
 */
console.log('Тест 1: комната.парами = false (или отсутствует)');
const комната1 = создатьМокКомнату({
  парами: false,
  мест: 4,
  игрокиДанные: [
    { телеграм: 11111, имя: 'Игрок 1' },
    { телеграм: 22222, имя: 'Игрок 2' },
    { телеграм: 33333, имя: 'Игрок 3' },
    { телеграм: 44444, имя: 'Игрок 4' }
  ]
});

const результат1 = комнаты.застольеДляРейтинга(комната1);
проверить('результат содержит 4 игроков', результат1.length === 4);
проверить('Игрок 1 имеет напарник: null', результат1[0].напарник === null);
проверить('Игрок 2 имеет напарник: null', результат1[1].напарник === null);
проверить('Игрок 3 имеет напарник: null', результат1[2].напарник === null);
проверить('Игрок 4 имеет напарник: null', результат1[3].напарник === null);


/**
 * ТЕСТ 2: Парами, 4 места — правильно спарены
 * Напарники: место 0 (телеграм 11111) ↔ место 2 (телеграм 33333)
 *            место 1 (телеграм 22222) ↔ место 3 (телеграм 44444)
 */
console.log('\nТест 2: комната.парами = true, 4 места — правильные пары');
const комната2 = создатьМокКомнату({
  парами: true,
  мест: 4,
  игрокиДанные: [
    { телеграм: 11111, имя: 'Игрок 1' },
    { телеграм: 22222, имя: 'Игрок 2' },
    { телеграм: 33333, имя: 'Игрок 3' },
    { телеграм: 44444, имя: 'Игрок 4' }
  ]
});

const результат2 = комнаты.застольеДляРейтинга(комната2);
проверить('результат содержит 4 игроков', результат2.length === 4);
// Место 0 (телеграм 11111) должно иметь напарника с места 2 (телеграм 33333)
проверить('Игрок 1 (место 0) имеет напарника 33333 (место 2)',
  результат2[0].напарник === 33333);
// Место 1 (телеграм 22222) должно иметь напарника с места 3 (телеграм 44444)
проверить('Игрок 2 (место 1) имеет напарника 44444 (место 3)',
  результат2[1].напарник === 44444);
// Место 2 (телеграм 33333) должно иметь напарника с места 0 (телеграм 11111)
проверить('Игрок 3 (место 2) имеет напарника 11111 (место 0)',
  результат2[2].напарник === 11111);
// Место 3 (телеграм 44444) должно иметь напарника с места 1 (телеграм 22222)
проверить('Игрок 4 (место 3) имеет напарника 22222 (место 1)',
  результат2[3].напарник === 22222);


/**
 * ТЕСТ 3: Парами, но один из напарников уже вышел и был удалён.
 * Сценарий: игра парами (4 места), но место 2 (место напарника места 0)
 * было удалено из комнаты.игроки (например, игрок вышел после партии).
 * В результат не должно попасть удалённое место, а место 0 должно получить
 * напарник: null (потому что игроков[местоНапарника] будет undefined).
 */
console.log('\nТест 3: парами, но напарник был удалён из комната.игроки');
const комната3 = создатьМокКомнату({
  парами: true,
  мест: 4,
  игрокиДанные: [
    { телеграм: 11111, имя: 'Игрок 1' },
    { телеграм: 22222, имя: 'Игрок 2' },
    { телеграм: 33333, имя: 'Игрок 3' },
    { телеграм: 44444, имя: 'Игрок 4' }
  ]
});

// Удалить место 2 (напарника места 0)
delete комната3.игроки['бот-3'];

const результат3 = комнаты.застольеДляРейтинга(комната3);
// Результат содержит только 3 игроков (место 2 было удалено)
проверить('результат содержит 3 игроков (место 2 удалено)', результат3.length === 3);
// Место 0 должно получить напарник: null (так как его напарник удалён)
проверить('Игрок на месте 0 имеет напарник: null (напарник удалён)',
  результат3[0].напарник === null);
// Место 1 (место 1 в оригинале) остаётся с напарником места 3
проверить('Игрок на месте 1 имеет напарника 44444 (место 3 всё ещё есть)',
  результат3[1].напарник === 44444);
// Место 3 (место 3 в оригинале) остаётся с напарником места 1
проверить('Игрок на месте 3 имеет напарника 22222 (место 1 всё ещё есть)',
  результат3[2].напарник === 22222);


/**
 * ТЕСТ 4: Проверка других полей наряду с напарником
 */
console.log('\nТест 4: все поля результата присутствуют и верны');
const комната4 = создатьМокКомнату({
  парами: true,
  мест: 4,
  игрокиДанные: [
    { телеграм: 11111, имя: 'Первый', этоБот: false, уровень: 'лёгкий' },
    { телеграм: 22222, имя: 'Второй', этоБот: true, уровень: 'сложный' },
    { телеграм: 33333, имя: 'Третий', этоБот: false },
    { телеграм: 44444, имя: 'Четвёртый', этоБот: true }
  ]
});

const результат4 = комнаты.застольеДляРейтинга(комната4);
проверить('первый игрок имеет номер телеграма', результат4[0].номер === 11111);
проверить('первый игрок имеет имя', результат4[0].имя === 'Первый');
проверить('первый игрок не бот', результат4[0].этоБот === false);
проверить('первый игрок имеет уровень', результат4[0].уровень === 'лёгкий');
проверить('первый игрок имеет поле парами', результат4[0].парами === true);
проверить('первый игрок имеет поле напарник', результат4[0].напарник === 33333);
проверить('второй игрок — бот', результат4[1].этоБот === true);


/**
 * ТЕСТ 5: Проверка победил/ничья (убедиться, что функция вообще работает)
 */
console.log('\nТест 5: парами с разным исходом (победил/проиграл)');
const комната5 = создатьМокКомнату({
  парами: true,
  мест: 4,
  игрокиДанные: [
    { телеграм: 11111, имя: 'Победитель 1' },
    { телеграм: 22222, имя: 'Проигравший 1' },
    { телеграм: 33333, имя: 'Победитель 2' },
    { телеграм: 44444, имя: 'Проигравший 2' }
  ]
});
комната5.партия.проигравшие = ['бот', 'бот-4'];  // проигравшие на местах 1 и 3

const результат5 = комнаты.застольеДляРейтинга(комната5);
проверить('результат содержит 4 игроков', результат5.length === 4);
проверить('человек победил', результат5[0].победил === true);
проверить('человек имеет напарника 33333', результат5[0].напарник === 33333);
проверить('бот проиграл', результат5[1].победил === false);
проверить('бот имеет напарника 44444', результат5[1].напарник === 44444);
проверить('бот-3 победил', результат5[2].победил === true);
проверить('бот-4 проиграл', результат5[3].победил === false);

console.log('\n' + '='.repeat(60));
console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
if (провалов > 0) {
  process.exit(1);
}
