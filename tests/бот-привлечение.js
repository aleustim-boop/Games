/** Собираем стенд. «ломка» — функция «текст бот.js → испорченный текст»
    для ломающего запуска; если порча ничего не изменила, это беда самой
    проверки: значит, она смотрит не туда. */
function собратьСтенд(ломка) {
  const рут = fs.mkdtempSync(path.join(os.tmpdir(), 'бот-привлечение-'));
  временныеПапки.push(рут);
  const папкаБота = path.join(рут, 'bot');
  const папкаСервера = path.join(рут, 'server');
  fs.mkdirSync(папкаБота);
  fs.mkdirSync(папкаСервера);

  for (const имя of fs.readdirSync(path.join(КОРЕНЬ, 'bot'))) {
    if (!имя.endsWith('.js') || имя.indexOf('проверка-') === 0) continue;
    let текст = fs.readFileSync(path.join(КОРЕНЬ, 'bot', имя), 'utf8');
    if (ломка && имя === 'бот.js') {
      const испорченный = ломка(текст);
      if (испорченный === текст) {
        throw new Error('ломающий запуск: порча не нашла в bot/бот.js свою строку — ' +
          'проверку чинить раньше, чем верить её зелёному цвету');
      }
      текст = испорченный;
    }
    fs.writeFileSync(path.join(папкаБота, имя), текст, 'utf8');
  }

  fs.copyFileSync(ИСХОДНЫЕ_НАЗВАНИЯ, path.join(папкаСервера, 'названия.js'));
  fs.writeFileSync(path.join(папкаБота, '.env'),
    'BOT_TOKEN=' + выдуманныйТокен() + '\nGAME_URL=' + GAME_URL + '\nOWNER_ID=' + ВЛАДЕЛЕЦ + '\n', 'utf8');

  return path.join(папкаБота, 'бот.js');
}

let номерАпдейта = 1000;

/** Сообщение «от человека». Текста может не быть — так выглядит служебная
    весть («в чат вошёл участник»). */
function сообщение(чат, типЧата, кто, текст, добавка) {
  const письмо = {
    message_id: 1,
    chat: { id: чат, type: типЧата },
    from: { id: кто, first_name: 'Игрок', is_bot: false }
  };
  if (текст) письмо.text = текст;
  return { update_id: ++номерАпдейта, message: Object.assign(письмо, добавка || {}) };
}

/** Весть «положение бота в чате изменилось». */
function перемена(чат, типЧата, кто, был, стал) {
  return {
    update_id: ++номерАпдейта,
    my_chat_member: {
      chat: { id: чат, type: типЧата },
      from: { id: кто, first_name: 'Игрок', is_bot: false },
      old_chat_member: { status: был },
      new_chat_member: { status: стал }
    }
  };
}

/** Запускаем свежего бота на стенде, отдаём ему пачку апдейтов и ждём,
    пока он разберёт её ВСЮ: бот спрашивает getUpdates второй раз только
    после ответа на последний апдейт пачки. Возвращаем всё, что он сказал
    Telegram за это время, и путь к его файлу статистики. */
async function прогнать(ломка, апдейты) {
  const путьКБоту = собратьСтенд(ломка);
  очередьОбновлений = апдейты;
  const началоОтправок = ОТПРАВЛЕНО.length;
  const счётДоЗапроса = счётЗапросовGetUpdates;

  /* Бот при запуске подробно рассказывает о себе в консоль — в отчёте
     проверки этот рассказ только мешает, поэтому на время разбора пачки
     его глушим. Ошибки (console.error) остаются слышны. */
  const настоящийЛог = console.log;
  console.log = function () {};
  try {
    require(путьКБоту);   // запускает работать() тут же, внутри процесса проверки

    for (let раз = 0; раз < 500 && счётЗапросовGetUpdates < счётДоЗапроса + 2; раз++) {
      await пауза(10);
    }
  } finally {
    console.log = настоящийЛог;
  }
  if (счётЗапросовGetUpdates < счётДоЗапроса + 2) {
    throw new Error('бот на стенде не дошёл до второго запроса новостей — стенд не работает');
  }

  let статистика = null;
  try {
    статистика = JSON.parse(fs.readFileSync(
      path.join(path.dirname(путьКБоту), 'данные', 'статистика.json'), 'utf8'));
  } catch (ошибка) { /* файла нет — проверки ниже скажут об этом сами */ }

  return { сказано: ОТПРАВЛЕНО.slice(началоОтправок), статистика: статистика };
}

/** Ответы бота в один чат (sendMessage и sendPhoto). */
function ответыВЧат(сказано, чат) {
  return сказано.filter(function (з) {
    return (з.метод === 'sendMessage' || з.метод === 'sendPhoto') && з.тело.chat_id === чат;
  });
}

function текстОтвета(ответ) {
  return String((ответ && ответ.тело && (ответ.тело.text || ответ.тело.caption)) || '');
}

// ---------------------------------------------------------------------------
// Сценарии. Возвращают список бед: пустой — всё в порядке.
// ---------------------------------------------------------------------------

async function всеСценарии(ломка, печатать) {
  const беды = [];
  let проверок = 0;
  function проверить(описание, условие, подробности) {
    проверок++;
    if (условие) {
      if (печатать) console.log('  ок   — ' + описание);
      return;
    }
    беды.push(описание);
    if (печатать) console.log('  СБОЙ — ' + описание + (подробности ? '\n         ' + подробности : ''));
  }

  // --- 1 и 2. Размеченная ссылка в личке и кнопка «Добавить в свой чат»
  if (печатать) console.log('1. Размеченная ссылка и кнопки в личке');
  const личка = await прогнать(ломка, [
    сообщение(111, 'private', 111, '/start src_habr'),
    сообщение(112, 'private', 112, '/start src_ПЛОХАЯ'),
    сообщение(113, 'private', 113, '/start invite_shashki'),
    сообщение(114, 'private', 114, '/start src_Habr')
  ]);
  const ответЛички = ответыВЧат(личка.сказано, 111)[0];
  проверить('на «/start src_habr» бот отвечает обычным приветствием',
    текстОтвета(ответЛички).indexOf('Жмите «Играть» и выбирайте') !== -1,
    'текст был: ' + текстОтвета(ответЛички));

  const клавиши = (ответЛички && ответЛички.тело.reply_markup && ответЛички.тело.reply_markup.inline_keyboard) || [];
  const всеКнопки = [].concat.apply([], клавиши);
  const кнопкаВЧат = всеКнопки.filter(function (к) { return к.text === 'Добавить в свой чат'; })[0];
  проверить('в личке есть кнопка «Добавить в свой чат»', !!кнопкаВЧат,
    'кнопки были: ' + JSON.stringify(всеКнопки.map(function (к) { return к.text; })));
  проверить('её ссылка — t.me/ТестБот?startgroup=src_group',
    !!кнопкаВЧат && кнопкаВЧат.url === 'https://t.me/ТестБот?startgroup=src_group',
    'url был: ' + (кнопкаВЧат && кнопкаВЧат.url));
  проверить('кнопка «Играть» осталась первой', !!клавиши[0] && клавиши[0][0].text === 'Играть');

  const люди = (личка.статистика && личка.статистика.люди) || {};
  проверить('пришедший по размеченной ссылке записан с источником «ссылка» и меткой habr',
    !!люди['111'] && люди['111'].источник === 'ссылка' && люди['111'].метка === 'habr',
    'запись: ' + JSON.stringify(люди['111']));
  проверить('метка с заглавной буквой («src_Habr») — та же habr, а не «приглашение друга»',
    !!люди['114'] && люди['114'].источник === 'ссылка' && люди['114'].метка === 'habr',
    'запись: ' + JSON.stringify(люди['114']));
  проверить('в счёте меток: habr — два человека',
    !!личка.статистика && !!личка.статистика.метки && личка.статистика.метки.habr === 2,
    'метки: ' + JSON.stringify(личка.статистика && личка.статистика.метки));
  проверить('метка с недопустимыми знаками в счёт не попала (метка одна)',
    !!личка.статистика && Object.keys(личка.статистика.метки || {}).length === 1,
    'метки: ' + JSON.stringify(личка.статистика && личка.статистика.метки));
  проверить('ссылка-приглашение друга по-прежнему считается «приглашением»',
    !!люди['113'] && люди['113'].источник === 'приглашение' && !люди['113'].метка,
    'запись: ' + JSON.stringify(люди['113']));

  // --- 3. Карточка бота при запуске (берём из того же запуска)
  if (печатать) console.log('2. Карточка бота при запуске');
  function вызовы(метод) {
    return личка.сказано.filter(function (з) { return з.метод === метод; });
  }
  const описание = (вызовы('setMyDescription')[0] || { тело: {} }).тело.description || '';
  проверить('описание бота поставлено и влезает в 512 знаков',
    описание.length > 0 && описание.length <= 512, 'длина: ' + описание.length);
  проверить('описание говорит про команду /play', описание.indexOf('/play') !== -1, 'описание: ' + описание);
  const короткое = (вызовы('setMyShortDescription')[0] || { тело: {} }).тело.short_description || '';
  проверить('короткая строка поставлена и влезает в 120 знаков',
    короткое.length > 0 && короткое.length <= 120, 'длина: ' + короткое.length);

  const спискиКоманд = вызовы('setMyCommands');
  const области = спискиКоманд.map(function (з) { return з.тело.scope && з.тело.scope.type; }).sort();
  проверить('подсказки команд поставлены и для личек, и для групп',
    JSON.stringify(области) === JSON.stringify(['all_group_chats', 'all_private_chats']),
    'области: ' + JSON.stringify(области));
  const всеКоманды = [].concat.apply([], спискиКоманд.map(function (з) { return з.тело.commands || []; }));
  // Telegram берёт в подсказку только латиницу в нижнем регистре, цифры и «_»
  проверить('имена команд — только латиница, цифры и «_» (иначе Telegram откажет)',
    всеКоманды.length > 0 && всеКоманды.every(function (к) {
      return /^[a-z0-9_]{1,32}$/.test(к.command) && к.description.length >= 1 && к.description.length <= 256;
    }), 'команды: ' + JSON.stringify(всеКоманды));
  проверить('в подсказках для групп есть play',
    спискиКоманд.some(function (з) {
      return з.тело.scope && з.тело.scope.type === 'all_group_chats' &&
        (з.тело.commands || []).some(function (к) { return к.command === 'play'; });
    }));
  const запросНовостей = вызовы('getUpdates')[0] || { тело: {} };
  проверить('бот просит у Telegram вести my_chat_member',
    (запросНовостей.тело.allowed_updates || []).indexOf('my_chat_member') !== -1,
    'allowed_updates: ' + JSON.stringify(запросНовостей.тело.allowed_updates));

  // --- 4. Бота добавили в группу и убрали
  if (печатать) console.log('3. Бота добавили в группу');
  const группы = await прогнать(ломка, [
    перемена(-500, 'supergroup', 201, 'left', 'member'),
    сообщение(-500, 'supergroup', 201, '/start@ТестБот src_group'),
    перемена(-500, 'supergroup', 201, 'member', 'administrator'),
    перемена(-501, 'group', 202, 'left', 'member'),
    перемена(-501, 'group', 202, 'member', 'kicked'),
    перемена(-502, 'channel', 203, 'left', 'administrator')
  ]);
  const приветствия = ответыВЧат(группы.сказано, -500);
  проверить('в группе бот поздоровался ровно один раз (весть + команда от Telegram — не два приветствия)',
    приветствия.length === 1, 'ответов в чат: ' + приветствия.length);
  проверить('приветствие группы называет команды /играть и /play',
    текстОтвета(приветствия[0]).indexOf('Напишите /играть или /play') !== -1,
    'текст был: ' + текстОтвета(приветствия[0]));
  const кнопкаГруппы = приветствия[0] && приветствия[0].тело.reply_markup &&
    приветствия[0].тело.reply_markup.inline_keyboard[0][0];
  проверить('под приветствием кнопка-ссылка в мини-приложение (не web_app — в группах он не работает)',
    !!кнопкаГруппы && typeof кнопкаГруппы.url === 'string' &&
    кнопкаГруппы.url.indexOf('https://t.me/ТестБот/BoardGames') === 0 && !кнопкаГруппы.web_app,
    'кнопка: ' + JSON.stringify(кнопкаГруппы));
  проверить('в канал бот не пишет', ответыВЧат(группы.сказано, -502).length === 0);

  const счётГрупп = (группы.статистика && группы.статистика.группы) || {};
  проверить('группа, где бот остался, в счёте и не помечена убранной',
    !!счётГрупп['-500'] && !счётГрупп['-500'].убран, 'запись: ' + JSON.stringify(счётГрупп['-500']));
  проверить('группа, откуда бота убрали, помечена убранной',
    !!счётГрупп['-501'] && !!счётГрупп['-501'].убран, 'запись: ' + JSON.stringify(счётГрупп['-501']));
  проверить('канал в счёт групп не попал', !счётГрупп['-502']);

  // --- 5 и 6. Чужой разговор в группе и команда /play
  if (печатать) console.log('4. В группе бот отвечает только на свои команды');
  const разговор = await прогнать(ломка, [
    сообщение(-600, 'group', 301, 'привет всем, как дела'),
    сообщение(-601, 'group', 302, '', { new_chat_members: [{ id: 999, first_name: 'Новый', is_bot: false }] }),
    сообщение(-602, 'group', 303, '/play@ДругойБот'),
    сообщение(-603, 'group', 304, '/что@ТестБот'),
    сообщение(-604, 'group', 305, '/play'),
    сообщение(-605, 'group', 306, '/PLAY@тестбот'),
    сообщение(-606, 'group', 307, '/help'),
    сообщение(-607, 'group', ВЛАДЕЛЕЦ, '/stats'),
    сообщение(ВЛАДЕЛЕЦ, 'private', ВЛАДЕЛЕЦ, '/stats')
  ]);
  проверить('на чужую команду без имени («/help») бот в группе молчит',
    ответыВЧат(разговор.сказано, -606).length === 0,
    'ответы: ' + JSON.stringify(ответыВЧат(разговор.сказано, -606).map(текстОтвета)));
  const отчётВГруппе = ответыВЧат(разговор.сказано, -607).map(текстОтвета).join('\n');
  проверить('владельцу в группе бот отчёт не показывает, а зовёт в личку',
    отчётВГруппе.indexOf('только в личной переписке') !== -1 && отчётВГруппе.indexOf('Всего людей') === -1 &&
    отчётВГруппе.indexOf('размеченн') === -1, 'текст был: ' + отчётВГруппе);
  const отчётВЛичке = ответыВЧат(разговор.сказано, ВЛАДЕЛЕЦ).map(текстОтвета).join('\n');
  проверить('в личке владелец отчёт по-прежнему получает',
    отчётВЛичке.length > 0 && отчётВЛичке.indexOf('только в личной переписке') === -1 &&
    отчётВЛичке !== отчётВГруппе, 'текст был: ' + отчётВЛичке);
  проверить('на обычную реплику в группе бот молчит', ответыВЧат(разговор.сказано, -600).length === 0);
  проверить('на служебную весть (вошёл участник) бот молчит', ответыВЧат(разговор.сказано, -601).length === 0);
  проверить('на команду другому боту бот молчит', ответыВЧат(разговор.сказано, -602).length === 0);
  const людиГруппы = (разговор.статистика && разговор.статистика.люди) || {};
  проверить('молчаливые случаи не считаются заходами к боту',
    !людиГруппы['301'] && !людиГруппы['302'] && !людиГруппы['303'] && !людиГруппы['307'],
    'люди: ' + JSON.stringify(Object.keys(людиГруппы)));

  const общийОтвет = текстОтвета(ответыВЧат(разговор.сказано, -603)[0]);
  проверить('на свою незнакомую команду в группе — прежняя подсказка про /играть',
    общийОтвет.indexOf('Напишите /играть — соберу стол прямо здесь') !== -1, 'текст был: ' + общийОтвет);
  for (const чат of [-604, -605]) {
    const ответыСтола = ответыВЧат(разговор.сказано, чат);
    проверить('команда /play (чат ' + чат + ') спрашивает, во что играем, а не шлёт общую подсказку',
      ответыСтола.length === 1 && текстОтвета(ответыСтола[0]) === 'Во что играем?',
      'ответы: ' + JSON.stringify(ответыСтола.map(текстОтвета)));
  }

  return { беды: беды, проверок: проверок };
}

