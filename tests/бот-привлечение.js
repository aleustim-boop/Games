/* =====================================================================
   Проверка: то, чем бот помогает приводить людей (штаб/план-привлечение.md).

   Что проверяем:
     1. размеченная ссылка «/start src_<метка>» — человек получает обычное
        приветствие, а в статистике остаётся источник «ссылка» и метка;
     2. в личке есть кнопка «Добавить в свой чат» со ссылкой ?startgroup=;
     3. при запуске бот ставит описание, короткую строку и подсказки команд,
        и всё это укладывается в пределы Telegram;
     4. бота добавили в группу (my_chat_member) — он здоровается ОДИН раз,
        даже если следом пришла команда «/start@Бот src_group», и группа
        попадает в счёт; убрали — в счёте отмечено;
     5. в группе бот молчит на чужой разговор: обычную реплику, служебную
        весть и команду другому боту;
     6. латинская «/play» работает так же, как «/играть»: спрашивает, во что играем.

   Стенд — тот же приём, что в tests/бот-приглашение-в-игру.js: копия
   bot/*.js и server/названия.js во временной папке, ПОДДЕЛЬНЫЙ .env
   с выдуманным токеном, подменённый https.request. Настоящий bot/.env
   не читается, в настоящий Telegram ничего не уходит.

   Ломающие запуски — в конце: копию бот.js портим семью способами по
   очереди, и на каждой порче проверка обязана покраснеть.

   Запуск:  node tests/бот-привлечение.js
   ===================================================================== */

'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const https = require('https');
const { EventEmitter } = require('events');

const КОРЕНЬ = path.join(__dirname, '..');
const ИСХОДНЫЕ_НАЗВАНИЯ = path.join(КОРЕНЬ, 'server', 'названия.js');

const временныеПапки = [];

/* Каждый бот на стенде вешает свой обработчик Ctrl+C, а ботов здесь
   десятки — без этой строки Node ругается на «утечку» обработчиков. */
process.setMaxListeners(0);

function пауза(мс) { return new Promise(function (готово) { setTimeout(готово, мс); }); }

/* Выдуманный токен собран из кусочков — GitHub узнаёт токены Telegram
   по виду строки и присылает ложную тревогу об утечке, если написать
   его одной строкой (см. объяснение в tests/проверка-бота-лаунчера.js). */
function выдуманныйТокен() {
  const номерБота = [1, 2, 3, 4, 5, 6, 7, 8, 9, 0].join('');
  return номерБота + ':' + 'тест'.repeat(9);
}

/* Адрес игры нарочно без «?сервер=»: сервер комнат этой проверке не нужен,
   а без адреса бот к нему и не пойдёт. */
const GAME_URL = 'https://игра.пример/сборник';

/* Владелец на стенде: ему и только ему бот показывает /статистика. */
const ВЛАДЕЛЕЦ = 777;

// ---------------------------------------------------------------------------
// Поддельный Telegram: подменяем https.request на весь процесс
// ---------------------------------------------------------------------------

const ОТПРАВЛЕНО = [];       // {метод, тело} — всё, что бот сказал Telegram, включая getUpdates
let очередьОбновлений = [];  // апдейты, которые отдаём на ближайший запрос getUpdates
let счётЗапросовGetUpdates = 0;

https.request = function (опции, колбэк) {
  const запрос = new EventEmitter();
  запрос.end = function (телоBuf) {
    let тело = {};
    try { тело = телоBuf ? JSON.parse(телоBuf.toString('utf8')) : {}; } catch (ошибка) { /* не важно */ }
    const путь = String((опции && опции.path) || '');
    const метод = путь.slice(путь.lastIndexOf('/') + 1);

    function ответить(результат, задержкаМс) {
      setTimeout(function () {
        const ответ = new EventEmitter();
        ответ.setEncoding = function () {};
        ответ.statusCode = 200;
        колбэк(ответ);
        ответ.emit('data', JSON.stringify({ ok: true, result: результат }));
        ответ.emit('end');
      }, задержкаМс || 0);
    }

    ОТПРАВЛЕНО.push({ метод: метод, тело: тело });

    if (метод === 'getUpdates') {
      счётЗапросовGetUpdates++;
      if (очередьОбновлений.length) {
        const пачка = очередьОбновлений;
        очередьОбновлений = [];
        ответить(пачка, 0);
      } else {
        /* Пустой ответ — через десять минут: отработавшие боты прежних
           сценариев не умирают, и быстрый пустой ответ позволил бы им
           перехватить апдейты следующего сценария (та же гонка разобрана
           в tests/бот-приглашение-в-игру.js). */
        ответить([], 10 * 60 * 1000);
      }
      return;
    }

    if (метод === 'getMe') { ответить({ username: 'ТестБот' }); return; }
    if (метод === 'sendMessage' || метод === 'sendPhoto') { ответить({ message_id: 1 }); return; }
    ответить(true);
  };
  запрос.on = EventEmitter.prototype.on.bind(запрос);
  запрос.destroy = function () {};
  return запрос;
};

