/* (1) К1 и (3) К10 — на одном столе: Боря спит в раунде 1. */
сценарий('(1) К1: опоздавшее «Готово» спящего — отказ до пробуждения; (3) К10: «проснуться»', function (новый) {
  const с = новый({ игра: 'захват', мест: 3, гости: ['Боря', 'Вера'] });
  начать(с);
  const к = с.комната;
  проверить(к.партия.раунд === 1, '(1) партия «Захвата» в раунде 1: ' + к.партия.раунд);
  уложитьСпать(с, с.Х);
  погаситьНасос(к);
  const х = к.игроки[с.Х];
  const номерДо = к.номерСобытия;

  const ответ = комнаты.сделатьХод(к, с.Х, { действие: 'готово', раунд: 0 });
  проверить(ответ.принято === false && ответ.причина === 'Раунд уже разыгран' && ответ.устарел === true,
    '(1) «Готово» с раундом 0 — отказ «Раунд уже разыгран»: ' + JSON.stringify(ответ));
  проверить(х.спит === true && х.этоБот === true, '(1) Боря по-прежнему спит, место водит бот: спит=' + х.спит + ', этоБот=' + х.этоБот);
  проверить(х.просрочекПодряд === 2, '(1) просрочки не обнулены: ' + х.просрочекПодряд);
  проверить(х.действиеВРаунде !== true, '(1) флажка действия нет: ' + х.действиеВРаунде);
  проверить(к.номерСобытия === номерДо, '(1) событий нет (ни «проснулся», ни хода): ' + номерДо + ' → ' + к.номерСобытия);
  проверить(Boolean(к.таймерБота) && Boolean(к.планБота) && к.планБота.кто === с.Х,
    '(1) насос ботов поднят: заведён ход бота за спящего: ' + JSON.stringify(к.планБота && { кто: к.планБота.кто }));

  // Без номера раунда — тоже опоздал (И1: поля нет — отказ).
  погаситьНасос(к);
  const безНомера = комнаты.сделатьХод(к, с.Х, { действие: 'изменить' });
  проверить(безНомера.принято === false && безНомера.причина === 'Раунд уже разыгран',
    '(1) «Изменить» без номера раунда — тот же отказ: ' + JSON.stringify(безНомера));
  проверить(х.спит === true && х.просрочекПодряд === 2 && х.действиеВРаунде !== true,
    '(1) и после него Боря спит, просрочки и флажок прежние');
  проверить(Boolean(к.таймерБота), '(1) и после него насос поднят');

  // (3) Дверь сна «Захвата» открыта: «проснуться» — принято, сон снят.
  const проснуться = комнаты.сделатьХод(к, с.Х, { действие: 'проснуться' });
  проверить(JSON.stringify(проснуться) === JSON.stringify({ принято: true }),
    '(3) «проснуться» у «Захвата» — { принято: true }: ' + JSON.stringify(проснуться));
  проверить(х.спит === false && х.этоБот === false && х.просрочекПодряд === 0, '(3) сон снят, место снова у человека');
  проверить(к.событие && к.событие.что === 'проснулся' && к.событие.кто === с.Х, '(3) событие «проснулся»: ' + JSON.stringify(к.событие));
  const ещёРаз = комнаты.сделатьХод(к, с.У, { действие: 'проснуться' });
  проверить(ещёРаз.принято === true, '(3) «проснуться» неспящей Веры — тоже принято: ' + JSON.stringify(ещёРаз));
});

/* (2) К2: флажок ставит принятое «Готово», новая партия снимает у всех. */
сценарий('(2) К2: флажок действиеВРаунде', function (новый) {
  const с = новый({ игра: 'захват', мест: 3, гости: ['Боря', 'Вера'] });
  начать(с);
  const к = с.комната;
  const люди = [с.А, с.Х, с.У];
  проверить(люди.every(м => к.игроки[м].действиеВРаунде === false), '(2) после раздачи флажок у всех false: ' +
    JSON.stringify(люди.map(м => к.игроки[м].действиеВРаунде)));

  const готово = комнаты.сделатьХод(к, с.А, { действие: 'готово', раунд: к.партия.раунд });
  проверить(готово.принято === true, '(2) «Готово» Ани с номером открытого раунда принято: ' + JSON.stringify(готово));
  проверить(к.игроки[с.А].действиеВРаунде === true, '(2) принятое «Готово» ставит флажок Ане');
  проверить(к.игроки[с.У].действиеВРаунде === false, '(2) у Веры, которая ничего не делала, флажка нет');

  // Конец партии: Боря и Вера сдаются, жива одна Аня.
  for (const м of [с.Х, с.У]) {
    const сдался = комнаты.сделатьХод(к, м, { действие: 'сдаться' });
    if (!сдался.принято) throw new Error('сдача не принята: ' + сдался.причина);
  }
  проверить(к.этап === 'конец', '(2) после двух сдач партия кончилась: этап ' + к.этап);
  const номерДо = к.номерПартии;
  for (const м of люди) {
    const ещё = комнаты.сделатьХод(к, м, { действие: 'ещё' });
    if (!ещё.принято) throw new Error('«ещё» не принято: ' + ещё.причина);
  }
  проверить(к.этап === 'игра' && к.номерПартии === номерДо + 1, '(2) «ещё» от всех — новая партия: этап ' + к.этап + ', № ' + к.номерПартии);
  проверить(люди.every(м => к.игроки[м].действиеВРаунде === false),
    '(2) новая партия сбросила флажок у всех: ' + JSON.stringify(люди.map(м => к.игроки[м].действиеВРаунде)));
});

/* (4) К11: люди за картой — без посаженного бота. */
сценарий('(4) К11: люди в настройках раздачи', function (новый) {
  const с = новый({ игра: 'захват', мест: 3, гости: ['Боря'], ботов: 1 });
  const бот = Object.keys(с.комната.игроки).find(м => с.комната.игроки[м] && с.комната.игроки[м].этоБот);
  проверить(Boolean(бот), '(4) за столом посажен бот');
  пойманоРаздать.захват.length = 0;
  начать(с);
  const к = с.комната;
  const настройки = пойманоРаздать.захват[0];
  проверить(пойманоРаздать.захват.length === 1, '(4) раздать «Захвата» позвана один раз: ' + пойманоРаздать.захват.length);
  const ждём = JSON.stringify([с.А, с.Х].sort());
  проверить(настройки && Array.isArray(настройки.люди) && JSON.stringify(настройки.люди.slice().sort()) === ждём,
    '(4) в раздать ушли люди = ключи людей ' + ждём + ': ' + JSON.stringify(настройки && настройки.люди));
  проверить(настройки && Array.isArray(настройки.люди) && настройки.люди.indexOf(бот) === -1, '(4) посаженного бота в людях нет');
  проверить(Array.isArray(к.партия.люди) && JSON.stringify(к.партия.люди.slice().sort()) === ждём,
    '(4) у партии люди = ключи людей: ' + JSON.stringify(к.партия.люди));
  проверить(к.партия.сЛюдьми === true, '(4) партия знает, что за картой люди');
});

