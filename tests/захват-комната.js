  const пропуска = { Аня: создано.пропуск };
  for (const имя of н.гости || []) {
    const вход = комнаты.войтиВКомнату(создано.код, { имя: имя, метка: 'zahvat-' + номерАдреса + '-' + ИМЕНА.indexOf(имя), телеграм: номер(имя) });
    if (!вход.ок) throw new Error('вход не удался: ' + вход.причина);
    пропуска[имя] = вход.пропуск;
  }
  const место = имя => пропуска[имя] ? комнаты.найтиИгрока(создано.код, пропуска[имя]).ктоЯ : null;
  const стол = {
    код: создано.код,
    комната: комнаты.найтиИгрока(создано.код, пропуска.Аня).комната,
    А: место('Аня'), Х: место('Боря'), У: место('Вера')
  };
