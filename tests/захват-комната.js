/**
 * Стол в прихожей: Аня — хозяйка, гости по списку, ботов — сколько сказано.
 * Партию не начинает. А — Аня, Х — Боря, У — Вера.
 */
function собратьСтол(н) {
  номерАдреса++;
  const номер = имя => 810000 + номерАдреса * 10 + ИМЕНА.indexOf(имя);
  const создано = комнаты.создатьКомнату('10.88.0.' + номерАдреса,
    { игра: н.игра, имя: 'Аня', мест: н.мест, телеграм: номер('Аня') });
  if (!создано.ок) throw new Error('комната «' + н.игра + '» не создалась: ' + создано.причина);
  const пропуска = { Аня: создано.пропуск };
  for (const имя of н.гости || []) {
    const вход = комнаты.войтиВКомнату(создано.код, { имя: имя, метка: 'zahvat-' + номерАдреса + '-' + ИМЕНА.indexOf(имя), телеграм: номер(имя) });
    if (!вход.ок) throw new Error('вход не удался: ' + вход.причина);
    пропуска[имя] = вход.пропуск;
  }
  const место = имя => пропуска[имя] ? комнаты.найтиИгрока(создано.код, пропуска[имя]).ктоЯ : null;
  const стол = {
    код: создано.код,
    пропуска: пропуска,
    комната: комнаты.найтиИгрока(создано.код, пропуска.Аня).комната,
    А: место('Аня'), Х: место('Боря'), У: место('Вера')
  };
  for (let и = 0; и < (н.ботов || 0); и++) {
    const сел = комнаты.сделатьХод(стол.комната, стол.А, { действие: 'бот' });
    if (!сел.принято) throw new Error('бот не сел: ' + сел.причина);
  }
  return стол;
}

function начать(стол) {
  const ответ = комнаты.сделатьХод(стол.комната, стол.А, { действие: 'начать' });
  if (!ответ.принято) throw new Error('партия не началась: ' + ответ.причина);
  if (стол.комната.этап !== 'игра') throw new Error('после «начать» этап ' + стол.комната.этап);
}

/** Усыпить место руками — так же, как это делает усыпить() в комнате после двух просрочек. */
function уложитьСпать(стол, ключ) {
  const игрок = стол.комната.игроки[ключ];
  игрок.спит = true;
  игрок.этоБот = true;
  игрок.уровень = стол.комната.уровеньБотов;
  игрок.просрочекПодряд = 2;
  игрок.просрочкаЭтойОчереди = true;
}

/** Погасить таймер бота, чтобы увидеть, поднимет ли его отказ. */
function погаситьНасос(комната) {
  if (комната.таймерБота) clearTimeout(комната.таймерБота);
  комната.таймерБота = null;
  комната.планБота = null;
}

/**
 * Срок раунда вышел: часы — на миг будильника срока, и звонит он сам, тем
 * же делом, что завела комната (сработалаПросрочка под безПадения).
 * Раньше срока — «рано»: часы не двигаем, звонок приходит до срока.
 */
function прозвонитьСрок(комната, рано) {
  const т = комната.таймерПросрочки;
  if (!т) throw new Error('будильник срока раунда не заведён');
  if (!рано && т.когда > часы) часы = т.когда;
  таймеры.delete(т);
  т.дело();
}

/**
 * Номер фразы «Захвата» по тексту — из каталога знаков игры. Без текста —
 * первая фраза на весь стол (адресат ей не нужен): фразу одному («Мир?»)
 * без адресата за столом на троих комната не примет (Б3ф).
 */
function номерФразы(текст) {
  for (let н = 0; н <= 500; н++) {
    if (!ЗнакиЗахвата.этоЗнак(н) || ЗнакиЗахвата.этоБросок(н)) continue;
    const слова = ЗнакиЗахвата.текст(н);
    if (ЗнакиЗахвата.ФРАЗЫ.indexOf(слова) === -1) continue;
    if (текст ? слова === текст : ЗнакиЗахвата.нужнаЦель(н) === false) return н;
  }
  return 0;
}

/** Своя область места и всё подкрепление на неё — черновик, который точно примут. */
function черновикНаВсё(п, ключ) {
  const область = п.хозяева.findIndex((х, н) => н > 0 && х === ключ);
  return { раунд: п.раунд, расстановка: { [область]: п.подкрепление[ключ] }, приказы: [] };
}

/**
 * Часы идут до мига «до»; по дороге звонят таймеры ЭТОЙ комнаты (ход бота,
 * срок раунда, «все готовы») — по порядку мигов, каждый своим делом, как
 * настоящие. Звонок мог завести новый таймер — он тоже позвонит, если успеет.
 */
function идтиДо(комната, до) {
  for (let шаг = 0; ; шаг++) {
    if (шаг > 200) throw new Error('таймеры комнаты звонят без конца — до ' + до);
    const свои = [комната.таймерБота, комната.таймерПросрочки, комната.таймерВсеГотовы]
      .filter(т => т && таймеры.has(т) && т.когда <= до);
    if (свои.length === 0) break;
    свои.sort((а, б) => а.когда - б.когда || а.номер - б.номер);
    const т = свои[0];
    if (т.когда > часы) часы = т.когда;
    таймеры.delete(т);
    т.дело();
  }
  if (до > часы) часы = до;
}

