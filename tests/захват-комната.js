  пойманоРаздать.домино.length = 0;
  начать(с);
  const настройки = пойманоРаздать.домино[0];
  проверить(Boolean(настройки), '(7) раздать домино поймана');
  проверить(настройки && !('люди' in настройки) && !('раундовЗахвата' in настройки),
    '(7) в раздать домино нет полей «люди» и «раундовЗахвата»: ' + JSON.stringify(Object.keys(настройки || {})));
  const люди = [с.А, с.Х, с.У];
  проверить(люди.every(м => !('действиеВРаунде' in к.игроки[м])), '(7) после раздачи у игроков домино флажка нет');
  const ответ = комнаты.сделатьХод(к, с.Х, { действие: 'проснуться' });
  проверить(ответ.принято === true, '(7) действие игрока домино принято: ' + JSON.stringify(ответ));
