  проверить(п.завершена === true, '(19) ' + как + ': партия кончилась');
  проверить(п.результат === null && (п.проигравшие || []).length === 0,
    '(19) ' + как + ': результат пустой, проигравших нет: ' + JSON.stringify({ результат: п.результат, проигравшие: п.проигравшие }));
  проверить(пойманоРейтинг.length === 0, '(19) ' + как + ': в рейтинг ничего не ушло: ' + пойманоРейтинг.length);
  const захватСтат = пойманоСтатистика.filter(з => з.игра === 'захват').map(з => з.что);
