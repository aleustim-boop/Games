function сценарий(название, дело) {
  console.log('\n' + название);
  try {
    дело(function (н) { const с = собратьСтол(н); открытыеСтолы.push(с.код); return с; });
  } catch (сбой) {
    проверить(false, название.slice(0, 4) + ' сценарий оборвался: ' + (сбой && сбой.stack || сбой));
  }
}

