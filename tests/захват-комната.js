/* (29) Срок раунда 40 с, выбранный хозяином, доезжает до будильника комнаты и до вида игрока. */
сценарий('(29) срок раунда: хозяин выбрал 40 с — партия, будильник и вид живут по 40; без выбора — по 60', function (новый) {
  const ПравилаЗахвата = require(path.join(ПАПКА, 'игры', 'захват', 'захват-правила.js'));
  const прибавка = ПравилаЗахвата.ЧИСЛА.прибавкаПервомуРаундуСекунд;
  const показ = ПравилаЗахвата.ЧИСЛА.разборНеРаньшеСекунд;
  проверить(прибавка > 0 && показ > 0, '(29) в правилах есть прибавка первому раунду и показ итогов: ' + прибавка + ', ' + показ);

  const проверитьСтол = function (лимит, ждём) {
    const подпись = '(29) ' + (лимит === null ? 'без настройки' : 'лимит ' + лимит) + ': ';
    const с = новый({ игра: 'захват', мест: 3, гости: ['Боря', 'Вера'] });
    if (лимит !== null) {
      const принят = комнаты.сделатьХод(с.комната, с.А, { действие: 'настройки', лимитСекундНаХод: лимит });
      проверить(принят.принято === true, подпись + 'хозяин прислал настройки, принято: ' + JSON.stringify(принят));
    }
    const старт = часы;
    начать(с);
    const к = с.комната;
    const п = к.партия;
    проверить(п.секундНаРаунд === ждём, подпись + 'партия.секундНаРаунд = ' + п.секундНаРаунд + ', ждали ' + ждём);
    проверить(Boolean(к.таймерПросрочки), подпись + 'будильник срока заведён');
    const доКонца1 = к.таймерПросрочки ? к.таймерПросрочки.когда - старт : null;
    проверить(доКонца1 === (ждём + прибавка) * 1000,
      подпись + 'первый будильник — через ' + (ждём + прибавка) + ' с от старта, а не иначе: ' + доКонца1 + ' мс');
    const вид1 = комнаты.показатьИгроку(к, с.А);
    const мс1 = вид1 && вид1.захват ? вид1.захват.мсДоКонца : undefined;
    проверить(к.таймерПросрочки && мс1 === к.таймерПросрочки.когда - часы,
      подпись + 'вид игрока: мсДоКонца ' + мс1 + ' совпадает с будильником');
    прозвонитьСрок(к);
    проверить(п.раунд === 2, подпись + 'первый раунд разобран по сроку, открыт ' + п.раунд);
    проверить(Boolean(к.таймерПросрочки), подпись + 'будильник второго раунда заведён');
    const доКонца2 = к.таймерПросрочки ? к.таймерПросрочки.когда - часы : null;
    проверить(доКонца2 === (показ + ждём) * 1000,
      подпись + 'после разбора срок = ' + показ + ' с показа + ' + ждём + ' с раунда: ' + доКонца2 + ' мс');
    const вид2 = комнаты.показатьИгроку(к, с.А);
    const мс2 = вид2 && вид2.захват ? вид2.захват.мсДоКонца : undefined;
    проверить(к.таймерПросрочки && мс2 === к.таймерПросрочки.когда - часы,
      подпись + 'вид после разбора: мсДоКонца ' + мс2 + ' совпадает с будильником');
  };
  проверитьСтол(40, 40);
  проверитьСтол(null, 60);
});

