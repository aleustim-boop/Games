function json(route, тело) {
  return route.fulfill({
    status: 200,
    contentType: 'application/json; charset=utf-8',
    body: JSON.stringify(тело)
  });
}

function телоЗапроса(request) {
  try { return JSON.parse(request.postData() || '{}'); } catch (сбой) { return {}; }
}

/** Один диспетчер на ВСЕ подделанные двери — второй перехватить() тут не
 *  зовём, повторные вызовы браузер-робот.js применяют молча только
 *  последний. */
async function диспетчер(route, request, адрес) {
  const метод = request.method();
  const тело = метод === 'POST' ? телоЗапроса(request) : {};

  if (/\/друзья-список(?:\?|$)/.test(адрес)) {
    журнал.push({ дверь: '/друзья-список', тело: тело });
    if (режимСписка === 'обрыв') { await route.abort('failed'); return; }
    if (режимСписка === 'пусто') {
      await json(route, { ок: true, узналиВас: true, друзья: [], входящие: [] });
      return;
    }
    await json(route, { ок: true, узналиВас: true, друзья: друзья, входящие: входящие });
    return;
  }
  if (/\/друзья-принять(?:\?|$)/.test(адрес)) {
    журнал.push({ дверь: '/друзья-принять', тело: тело });
    const заявка = входящие.find((з) => з.ключ === тело.ключ);
    if (заявка) {
      входящие = входящие.filter((з) => з !== заявка);
      друзья = друзья.concat([заявка]);
    }
    await json(route, { ок: true });
    return;
  }
  if (/\/друзья-отклонить(?:\?|$)/.test(адрес)) {
    журнал.push({ дверь: '/друзья-отклонить', тело: тело });
    входящие = входящие.filter((з) => з.ключ !== тело.ключ);
    await json(route, { ок: true });
    return;
  }
  if (/\/друзья-удалить(?:\?|$)/.test(адрес)) {
    журнал.push({ дверь: '/друзья-удалить', тело: тело });
    друзья = друзья.filter((д) => д.ключ !== тело.ключ);
    await json(route, { ок: true });
    return;
  }
  if (/\/друзья-позвать(?:\?|$)/.test(адрес)) {
    журнал.push({ дверь: '/друзья-позвать', тело: тело });
    const статус = тело.ключ === 'zn-vera' ? 'друзья' : 'ожидает';
    await json(route, { ок: true, статус: статус });
    return;
  }
  if (/\/знакомые(?:\?|$)/.test(адрес)) {
    журнал.push({ дверь: '/знакомые', тело: тело });
    await json(route, { узналиВас: true, знакомые: знакомые });
    return;
  }
  /* Опрос «кто здесь» (window.ЭкранДрузей.открыть() зовёт его сразу и
     потом раз в 30 с) — этому стенду важно только не увидеть отказ
     соединения, содержимое ни один из 8 сценариев не смотрит. */
  if (/\/друзья-онлайн(?:\?|$)/.test(адрес)) {
    журнал.push({ дверь: '/друзья-онлайн', тело: тело });
    await json(route, { узналиВас: true, меняВидно: true, друзья: [], входящихЗаявок: 0 });
    return;
  }
  if (/\/прятаться(?:\?|$)/.test(адрес)) {
    журнал.push({ дверь: '/прятаться', тело: тело });
    await json(route, { узналиВас: true, меняВидно: тело.прятаться !== true });
    return;
  }
  /* Три ФОНОВЫЕ двери на боевой 127.0.0.1:8790 (js/популярность.js,
     js/мой-аватар.js) — см. «ПРАВКА 26.09» в шапке файла. Их ответ ни
     один из сценариев не читает, важен только код 200 вместо отказа связи. */
  if (/\/(статистика|пульс|мой-аватар)(?:\?|$)/.test(адрес)) {
    журнал.push({ дверь: адрес.replace(/^.*(\/[^/?]+)(?:\?.*)?$/, '$1'), тело: тело });
    await json(route, { ок: false });
    return;
  }
  route.continue();
}

