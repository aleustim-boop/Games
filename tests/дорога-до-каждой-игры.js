/**
 * Проверка: дорога до каждой игры
 *
 * История: нарды были готовы (файл нарды.html существовал), но плитка
 * на витрине (index.html) стояла выключенной с пометкой «скоро» ещё сутки —
 * попасть в игру с витрины было нельзя, хотя напрямую по адресу игра открывалась.
 *
 * Проверка обеспечивает:
 * 1. Каждой плитке "скоро" (disabled) соответствует ОТСУТСТВИЕ файла страницы
 * 2. Каждой активной плитке соответствует НАЛИЧИЕ файла (или она содержится в index.html для дурака)
 *
 * Способ доказать, что проверка красна:
 * Ниже (в конце) — синтетический тест, где мы имитируем наличие файла домино.html
 * для плитки, помеченной "скоро". Функция проверки это ловит и выбрасывает ошибку.
 */

const fs = require('fs');
const path = require('path');

// Вспомогательная функция: парсить index.html и собрать данные о плитках
function собратьДанныеПлиток(содержимоеHtml) {
  const плитки = [];

  // Ищем кнопки и прямые ссылки с class="плитка-игры".
  // Используем простой regex, так как разметка структурирована
  const регулярка = /<(?:button|a)\b[^>]*class="([^"]*плитка-игры[^"]*)"[^>]*data-игра="([^"]*)"[^>]*>/g;

  let совпадение;
  while ((совпадение = регулярка.exec(содержимоеHtml)) !== null) {
    const класс = совпадение[1];
    const игра = совпадение[2];

    плитки.push({
      игра: игра,
      класс: класс,
      естьКлассСкоро: класс.includes('плитка-игры--скоро'),
    });
  }

  return плитки;
}

// Основная функция проверки
function проверитьДорогуДоКаждойИгры(диагностика = false) {
  const корень = path.join(__dirname, '..');
  const индексПуть = path.join(корень, 'index.html');

  if (!fs.existsSync(индексПуть)) {
    throw new Error(`index.html не найден по пути: ${индексПуть}`);
  }

  const содержимое = fs.readFileSync(индексПуть, 'utf8');
  const плитки = собратьДанныеПлиток(содержимое);

  if (плитки.length === 0) {
    throw new Error('Не найдено ни одной плитки с class="плитка-игры" в index.html');
  }

  const ошибки = [];

  for (const плитка of плитки) {
    const имяФайла = `${плитка.игра}.html`;
    const путьФайла = path.join(корень, имяФайла);
    const файлСуществует = fs.existsSync(путьФайла);

    if (плитка.естьКлассСкоро) {
      // Плитка помечена "скоро" — файла НЕ должно быть
      if (файлСуществует) {
        ошибки.push(
          `Плитка "${плитка.игра}" помечена "скоро" (disabled, класс плитка-игры--скоро), ` +
          `но файл ${имяФайла} уже существует в корне! ` +
          `Это та самая ошибка: страница готова, а плитка отстала от реальности.`
        );
      } else if (диагностика) {
        console.log(`✓ Плитка "скоро" "${плитка.игра}": файл ${имяФайла} отсутствует (правильно)`);
      }
    } else {
      // Плитка активна (нет класса "скоро") — должен быть файл
      // Исключение: дурак живёт на index.html
      if (плитка.игра === 'дурак') {
        if (диагностика) {
          console.log(`✓ Плитка "${плитка.игра}": живёт на index.html (правильно)`);
        }
      } else {
        if (!файлСуществует) {
          ошибки.push(
            `Плитка "${плитка.игра}" активна (нет класса плитка-игры--скоро), ` +
            `но файл ${имяФайла} не найден в корне проекта! ` +
            `Либо игра не готова (плитка должна быть помечена "скоро"), ` +
            `либо файл потерялся.`
          );
        } else if (диагностика) {
          console.log(`✓ Плитка "${плитка.игра}": файл ${имяФайла} существует (правильно)`);
        }
      }
    }
  }

  if (ошибки.length > 0) {
    const тексто = ошибки.join('\n\n');
    throw new Error(`Несоответствие между плитками витрины и файлами игр:\n\n${тексто}`);
  }

  return true;
}

