/**
 * Проверка: дорога до каждой игры
 *
 * История: нарды были готовы (файл нарды.html существовал), но плитка
 * на витрине (index.html) стояла выключенной с пометкой «скоро» ещё сутки —
 * попасть в игру с витрины было нельзя, хотя напрямую по адресу игра открывалась.
 *
 * Устройство витрины (проверено по index.html 29.09): плитки бывают двух
 * видов. Часть — ссылки <a href="freecell.html" data-игра="свободная-ячейка">:
 * дорога до игры — это href, а имя в data-игра может не совпадать с именем
 * файла (это как раз и есть «свободная-ячейка» → freecell.html). Часть —
 * кнопки <button data-игра="нарды"> без href вовсе (нарды, шахматы, шашки,
 * дурак): они переходят на страницу через JS (js/game.js, открытьНарды и
 * похожие функции) по имени игры, а дурак и вовсе живёт прямо на index.html.
 * У кнопок href в разметке принципиально нет — это не поломка, а способ
 * перехода; дорогу до них проверяем по-старому, через «имя-игры.html».
 *
 * Проверка обеспечивает:
 * 1. Каждой плитке "скоро" (disabled) соответствует ОТСУТСТВИЕ файла страницы
 * 2. Каждой активной плитке-ссылке (<a>) соответствует файл, на который
 *    в самом деле ведёт её href (а не название из data-игра — оно бывает
 *    другим); плитке-кнопке (<button>) — файл «имя-игры.html» (или она
 *    содержится в index.html для дурака)
 * 3. Ссылка без href, на внешний адрес или не на .html-файл — тоже провал:
 *    нажал — и никуда не попал
 *
 * Способ доказать, что проверка красна — два ломающих прогона:
 *   а) встроенный синтетический (без флага, часть обычного запуска):
 *      имитируем плитку "скоро" с "появившимся" файлом (сценарий кнопки);
 *   б) node tests/дорога-до-каждой-игры.js --сломать: собираем копию всех
 *      *.html файлов проекта во временной папке (fs.mkdtempSync внутри
 *      os.tmpdir()), меняем в копии index.html href одной настоящей
 *      активной плитки-ссылки на заведомо несуществующий файл — и
 *      проверка обязана покраснеть именно на нём (по имени игры, не
 *      только по счётчику). Настоящие файлы проекта при этом не трогаются
 *      никогда — портится только копия во временной папке, которая в
 *      конце удаляется (и только она, только если лежит внутри os.tmpdir()).
 */

const fs = require('fs');
const os = require('os');
const path = require('path');

// Вспомогательная функция: парсить index.html и собрать данные о плитках.
// Тег и href вытаскиваем из ПОЛНОГО текста открывающего тега — порядок
// атрибутов (class раньше data-игра или наоборот, href в начале или в
// конце) значения не имеет.
function собратьДанныеПлиток(содержимоеHtml) {
  const плитки = [];

  const регуляркаТега = /<(a|button)\b([^>]*)>/gi;
  let совпадение;
  while ((совпадение = регуляркаТега.exec(содержимоеHtml)) !== null) {
    const тег = совпадение[1].toLowerCase();
    const атрибуты = совпадение[2];

    const классМатч = /\bclass\s*=\s*"([^"]*)"/i.exec(атрибуты);
    const класс = классМатч ? классМатч[1] : '';
    if (!класс.includes('плитка-игры')) continue; // не плитка игры — не наше дело

    const игроМатч = /\bdata-игра\s*=\s*"([^"]*)"/i.exec(атрибуты);
    if (!игроМатч) continue; // плитка без data-игра — разбирать нечего

    const hrefМатч = /\bhref\s*=\s*"([^"]*)"/i.exec(атрибуты);

    плитки.push({
      игра: игроМатч[1],
      тег: тег,
      класс: класс,
      естьКлассСкоро: класс.includes('плитка-игры--скоро'),
      href: hrefМатч ? hrefМатч[1] : null,
    });
  }

  return плитки;
}

/* Разобрать href плитки-ссылки: вернуть имя файла (без ?query и #якоря)
   или объяснение, почему до файла добраться нельзя. */
function разобратьHref(сыройHref) {
  if (!сыройHref) {
    return { ок: false, причина: 'ссылка (<a>) без href вовсе: нажать и никуда не попасть' };
  }
  if (/^https?:\/\//i.test(сыройHref) || /^(mailto:|tel:)/i.test(сыройHref)) {
    return { ок: false, причина: `href ведёт на внешний адрес «${сыройHref}», а не на страницу игры внутри проекта` };
  }
  const безЯкоря = сыройHref.split('#')[0];
  const безЗапроса = безЯкоря.split('?')[0];
  if (!/\.html$/i.test(безЗапроса)) {
    return { ок: false, причина: `href «${сыройHref}» ведёт не на .html-страницу` };
  }
  return { ок: true, файл: безЗапроса };
}

// Основная функция проверки. Корень передаётся явно (не берётся из
// __dirname жёстко) — так один и тот же код можно прогнать и по
// настоящему проекту, и по испорченной копии во временной папке.
function проверитьДорогуДоКаждойИгры(корень, диагностика = false) {
  const индексПуть = path.join(корень, 'index.html');

  if (!fs.existsSync(индексПуть)) {
    throw new Error(`index.html не найден по пути: ${индексПуть}`);
  }

  const содержимое = fs.readFileSync(индексПуть, 'utf8');
  const плитки = собратьДанныеПлиток(содержимое);

  if (плитки.length === 0) {
    throw new Error('Не найдено ни одной плитки с class="плитка-игры" в index.html');
  }

  const ошибки = [];

  for (const плитка of плитки) {
    // Дурак — особый случай: кнопка без href, партия прямо на index.html.
    if (плитка.игра === 'дурак' && плитка.тег === 'button') {
      if (диагностика) console.log(`✓ Плитка "${плитка.игра}": живёт на index.html (правильно)`);
      continue;
    }

    let имяФайла;
    let источник;

    if (плитка.тег === 'a') {
      // Плитка-ссылка: дорога — это её href, а не «имя-игры.html»
      // (иначе «свободная-ячейка» ложно не найдёт freecell.html).
      const разобрано = разобратьHref(плитка.href);
      if (!разобрано.ок) {
        ошибки.push(`Плитка "${плитка.игра}": ${разобрано.причина}.`);
        continue;
      }
      имяФайла = разобрано.файл;
      источник = `href="${плитка.href}"`;
    } else {
      // Кнопка без href: переходит через JS на «имя-игры.html» (нарды,
      // шахматы, шашки и подобные) — href в разметке у неё нет по замыслу.
      имяФайла = `${плитка.игра}.html`;
      источник = 'data-игра (кнопка без href, переход через JS)';
    }

    const путьФайла = path.join(корень, имяФайла);
    const файлСуществует = fs.existsSync(путьФайла);

    if (плитка.естьКлассСкоро) {
      // Плитка помечена "скоро" — файла НЕ должно быть
      if (файлСуществует) {
        ошибки.push(
          `Плитка "${плитка.игра}" помечена "скоро" (disabled, класс плитка-игры--скоро), ` +
          `но файл ${имяФайла} уже существует в корне (${источник})! ` +
          `Это та самая ошибка: страница готова, а плитка отстала от реальности.`
        );
      } else if (диагностика) {
        console.log(`✓ Плитка "скоро" "${плитка.игра}": файл ${имяФайла} отсутствует (правильно)`);
      }
    } else {
      // Плитка активна (нет класса "скоро") — должен быть файл
      if (!файлСуществует) {
        ошибки.push(
          `Плитка "${плитка.игра}" активна (нет класса плитка-игры--скоро), ` +
          `но файл ${имяФайла} не найден в корне проекта (искали по ${источник})! ` +
          `Либо игра не готова (плитка должна быть помечена "скоро"), ` +
          `либо ссылка ведёт не туда.`
        );
      } else if (диагностика) {
        console.log(`✓ Плитка "${плитка.игра}": файл ${имяФайла} существует (${источник}) (правильно)`);
      }
    }
  }

  if (ошибки.length > 0) {
    const тексто = ошибки.join('\n\n');
    throw new Error(`Несоответствие между плитками витрины и файлами игр:\n\n${тексто}`);
  }

  return { плиток: плитки.length };
}

const КОРЕНЬ_ПРОЕКТА = path.join(__dirname, '..');

/* ---------------------------------------------------------------------
   Собрать во временной папке копию всех *.html файлов проекта. Портить
   будем только эту копию (см. запуститьЛомающийПрогон). Настоящие
   файлы здесь только читаются. */
function собратьВременнуюКопию() {
  const метка = 'дорога-до-каждой-игры-сломать-' + Date.now() + '-' + Math.random().toString(36).slice(2, 8);
  const папка = path.join(os.tmpdir(), метка);
  fs.mkdirSync(папка, { recursive: true });

  const страницы = fs.readdirSync(КОРЕНЬ_ПРОЕКТА).filter((имя) => /\.html$/i.test(имя));
  for (const имя of страницы) {
    fs.copyFileSync(path.join(КОРЕНЬ_ПРОЕКТА, имя), path.join(папка, имя));
  }

  return папка;
}

/* ---------------------------------------------------------------------
   ЛОМАЮЩИЙ ЗАПУСК (--сломать): портим КОПИЮ — у одной настоящей активной
   плитки-ссылки href меняем на заведомо несуществующий файл — и требуем,
   чтобы проверка покраснела именно на этой игре (по имени, не только
   по счётчику). */
function запуститьЛомающийПрогон() {
  const папка = собратьВременнуюКопию();

  function выйти(код) {
    if (папка && папка.startsWith(os.tmpdir())) {
      fs.rmSync(папка, { recursive: true, force: true });
    }
    process.exit(код);
  }

  if (!папка.startsWith(os.tmpdir())) {
    console.log('ОСТАНОВЛЕНО: временная папка оказалась не во временном каталоге системы — портить отказываюсь.');
    выйти(1);
    return;
  }

  const индексВКопии = path.join(папка, 'index.html');
  const текстДоПоломки = fs.readFileSync(индексВКопии, 'utf8');
  const плитки = собратьДанныеПлиток(текстДоПоломки);

  // Цель: любая активная (не "скоро") плитка-ссылка с href на реально
  // существующий .html-файл — её и подставим не туда.
  let цель = null;
  for (const плитка of плитки) {
    if (плитка.тег !== 'a' || плитка.естьКлассСкоро) continue;
    const разобрано = разобратьHref(плитка.href);
    if (!разобрано.ок) continue;
    if (fs.existsSync(path.join(КОРЕНЬ_ПРОЕКТА, разобрано.файл))) {
      цель = { игра: плитка.игра, href: плитка.href, файл: разобрано.файл };
      break;
    }
  }

  if (!цель) {
    console.log('Ломающий запуск не смог найти ни одной активной плитки-ссылки с рабочим href — портить нечего.');
    выйти(1);
    return;
  }

  const несуществующийHref = 'заведомо-не-существует-для-проверки.html';
  const строкаБыло = `href="${цель.href}"`;
  const строкаСтало = `href="${несуществующийHref}"`;

  if (!текстДоПоломки.includes(строкаБыло)) {
    console.log(`ЛОМАЮЩИЙ ЗАПУСК НЕ ПРИМЕНИЛСЯ: в копии не нашлась строка «${строкаБыло}».`);
    выйти(1);
    return;
  }

  const новыйТекст = текстДоПоломки.replace(строкаБыло, строкаСтало);
  fs.writeFileSync(индексВКопии, новыйТекст, 'utf8');

  // Сверка «текст копии не равен тексту оригинала» — с настоящим файлом
  // проекта, не тронутым.
  const настоящийТекст = fs.readFileSync(path.join(КОРЕНЬ_ПРОЕКТА, 'index.html'), 'utf8');
  const копияТекст = fs.readFileSync(индексВКопии, 'utf8');
  console.log(
    'Сверка «текст копии не равен тексту оригинала»: ' +
      (копияТекст !== настоящийТекст ? 'текст копии отличается — поломка применилась' : 'ПОЛОМКА НЕ ПРИМЕНИЛАСЬ')
  );
  if (копияТекст === настоящийТекст) {
    console.log('');
    console.log('ЛОМАЮЩИЙ ЗАПУСК ПРОВАЛЕН: копия не отличается от настоящего файла.');
    выйти(1);
    return;
  }

  console.log(`Портим копию: у плитки "${цель.игра}" href «${цель.href}» заменён на «${несуществующийHref}» (файла с таким именем нет).`);
  console.log('');

  try {
    проверитьДорогуДоКаждойИгры(папка, false);
    console.log('ЛОМАЮЩИЙ ЗАПУСК ВЫШЕЛ ЗЕЛЁНЫМ ТАМ, ГДЕ ДОЛЖЕН БЫЛ ПОКРАСНЕТЬ — проверка не ловит подставленную поломку.');
    console.log(`Временная копия для разбора: ${папка} (перед выходом будет удалена)`);
    выйти(1);
    return;
  } catch (ошибка) {
    const нашлось = ошибка.message.includes(цель.игра) && /не найден/.test(ошибка.message);
    console.log(`Проверка на испорченной копии: ${нашлось ? 'ПОКРАСНЕЛА, как ожидалось' : 'выдала другую ошибку'}.`);
    console.log(`  ${ошибка.message.split('\n').find((с) => с.includes(цель.игра)) || ошибка.message.split('\n')[0]}`);
    console.log('');
    console.log(`Временная копия для разбора: ${папка} (перед выходом будет удалена)`);
    if (!нашлось) {
      console.log('ЛОМАЮЩИЙ ЗАПУСК ПРОВАЛЕН: проверка упала не на той плитке, которую мы испортили.');
      выйти(1);
      return;
    }
    console.log('Ломающий запуск исправен: испорченный href найден проверкой именно по имени игры.');
    выйти(0);
  }
}

if (process.argv.includes('--сломать')) {
  запуститьЛомающийПрогон();
} else {
  // ============================================================================
  // ЗЕЛЁНЫЙ ПРОГОН: проверка работает правильно на реальном проекте
  // ============================================================================
  console.log('Зелёный прогон: проверяем реальный index.html и файлы...\n');

  let количествоПлиток = 0;

  try {
    const результат = проверитьДорогуДоКаждойИгры(КОРЕНЬ_ПРОЕКТА, true);
    количествоПлиток = результат.плиток;
    console.log('\n✓ Зелёный прогон ПРОШЁЛ: витрина и файлы согласованы.');
  } catch (ошибка) {
    console.error('✗ Зелёный прогон ПРОВАЛИЛСЯ:');
    console.error(ошибка.message);
    process.exit(1);
  }

  // ============================================================================
  // ВСТРОЕННЫЙ СИНТЕТИЧЕСКИЙ ЛОМАЮЩИЙ ПРОГОН: сценарий кнопки "скоро" с
  // "появившимся" файлом — проверяем правило 1 без подмены настоящих файлов.
  // Сценарий «href на несуществующий файл» проверяет отдельный --сломать
  // (копия на диске) — см. запуститьЛомающийПрогон выше.
  // ============================================================================
  console.log('\n---\n');
  console.log('Ломающий прогон (встроенный): имитируем ошибку (плитка "скоро", но файл существует)...\n');

  function проверитьССинтетическойОшибкой() {
    const выдуманнаяИгра = 'выдуманная-игра-для-проверки';
    const поддельнаяРазметка =
      `<button class="плитка-игры плитка-игры--скоро" data-игра="${выдуманнаяИгра}">Скоро</button>`;

    console.log(`  Подставляем поддельную плитку "скоро": "${выдуманнаяИгра}"`);
    console.log(`  Теперь имитируем: как будто файл ${выдуманнаяИгра}.html вдруг появился\n`);

    const оригиналReadFileSync = fs.readFileSync;
    const оригиналExistsSync = fs.existsSync;

    try {
      fs.readFileSync = function (путь, ...остальное) {
        if (path.basename(String(путь)) === 'index.html') {
          return поддельнаяРазметка;
        }
        return оригиналReadFileSync.call(fs, путь, ...остальное);
      };
      fs.existsSync = function (путь) {
        if (path.basename(String(путь)) === `${выдуманнаяИгра}.html`) {
          return true;
        }
        return оригиналExistsSync.call(fs, путь);
      };

      проверитьДорогуДоКаждойИгры(КОРЕНЬ_ПРОЕКТА, false);

      throw new Error(
        '✗ Синтетический тест провалился: проверка должна была выбросить ошибку, ' +
        `когда файл ${выдуманнаяИгра}.html "существует", но этого не произошло. ` +
        'Проверка не умеет краснеть!'
      );
    } catch (ошибка) {
      if (
        ошибка.message.includes(выдуманнаяИгра) &&
        ошибка.message.includes('скоро') &&
        ошибка.message.includes('помечена')
      ) {
        console.log(`  ✓ Проверка выловила синтетическую ошибку (как надо):`);
        const строкиОшибки = ошибка.message.split('\n').filter((с) => с.includes(выдуманнаяИгра));
        console.log(`    "${строкиОшибки[0] || ошибка.message.split('\n')[2]}"`);
        return true;
      } else if (ошибка.message.includes('Синтетический тест провалился')) {
        throw ошибка;
      } else {
        throw new Error(
          `Синтетический тест: неожиданная ошибка. ` +
          `Ожидали ошибку про выдуманную игру и скоро, получили: ${ошибка.message.split('\n')[0]}`
        );
      }
    } finally {
      fs.readFileSync = оригиналReadFileSync;
      fs.existsSync = оригиналExistsSync;
    }
  }

  try {
    проверитьССинтетическойОшибкой();
    console.log('\n✓ Ломающий прогон (встроенный) ПРОШЁЛ: проверка умеет краснеть на синтетической ошибке.');
  } catch (ошибка) {
    console.error('✗ Ломающий прогон (встроенный) ПРОВАЛИЛСЯ:');
    console.error(ошибка.message);
    process.exit(1);
  }

  console.log('\n---\n');
  console.log('Второй ломающий сценарий (href на несуществующий файл) — отдельным запуском:');
  console.log('  node tests/дорога-до-каждой-игры.js --сломать');

  // ============================================================================
  // ИТОГ
  // ============================================================================
  console.log('\n---\n');

  const всегоПроверок = количествоПлиток + 1;
  const всегоПровалов = 0;

  console.log(`Итого проверок: ${всегоПроверок}, провалов: ${всегоПровалов}`);
}
