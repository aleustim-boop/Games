console.log('\n---\n');
console.log('Ломающий прогон: имитируем ошибку (плитка "скоро", но файл существует)...\n');

function проверитьССинтетическойОшибкой() {
  // Не ищем плитку "скоро" на настоящей витрине — её там может не быть
  // (все игры готовы). Вместо этого сами создаём поддельную разметку
  // с одной плиткой "скоро" и подсовываем её проверке вместо index.html.
  const выдуманнаяИгра = 'выдуманная-игра-для-проверки';
  const поддельнаяРазметка =
    `<button class="плитка-игры плитка-игры--скоро" data-игра="${выдуманнаяИгра}">Скоро</button>`;

  console.log(`  Подставляем поддельную плитку "скоро": "${выдуманнаяИгра}"`);
  console.log(`  Теперь имитируем: как будто файл ${выдуманнаяИгра}.html вдруг появился\n`);

  const оригиналReadFileSync = fs.readFileSync;
  const оригиналExistsSync = fs.existsSync;

  try {
    fs.readFileSync = function (путь, ...остальное) {
      if (path.basename(String(путь)) === 'index.html') {
        return поддельнаяРазметка;
      }
      return оригиналReadFileSync.call(fs, путь, ...остальное);
    };
    fs.existsSync = function (путь) {
      if (path.basename(String(путь)) === `${выдуманнаяИгра}.html`) {
        return true;
      }
      return оригиналExistsSync.call(fs, путь);
    };

    // Теперь запустим проверку — она должна выбросить ошибку
    проверитьДорогуДоКаждойИгры(false);

    // Если дошли сюда — значит, проверка НЕ выловила нашу синтетическую ошибку
    throw new Error(
      '✗ Синтетический тест провалился: проверка должна была выбросить ошибку, ' +
      `когда файл ${выдуманнаяИгра}.html "существует", но этого не произошло. ` +
      'Проверка не умеет краснеть!'
    );
  } catch (ошибка) {
    if (
      ошибка.message.includes(выдуманнаяИгра) &&
      ошибка.message.includes('скоро') &&
      ошибка.message.includes('помечена')
    ) {
      // Отлично! Это именно та ошибка, которую мы ожидали
      console.log(`  ✓ Проверка выловила синтетическую ошибку (как надо):`);
      const строкиОшибки = ошибка.message.split('\n').filter(с => с.includes(выдуманнаяИгра));
      console.log(`    "${строкиОшибки[0] || ошибка.message.split('\n')[2]}"`);
      return true;
    } else if (ошибка.message.includes('Синтетический тест провалился')) {
      throw ошибка;
    } else {
      // Неожиданная ошибка
      throw new Error(
        `Синтетический тест: неожиданная ошибка. ` +
        `Ожидали ошибку про выдуманную игру и скоро, получили: ${ошибка.message.split('\n')[0]}`
      );
    }
  } finally {
    fs.readFileSync = оригиналReadFileSync;
    fs.existsSync = оригиналExistsSync;
  }
}

try {
  проверитьССинтетическойОшибкой();
  console.log('\n✓ Ломающий прогон ПРОШЁЛ: проверка умеет краснеть на синтетической ошибке.');
} catch (ошибка) {
  console.error('✗ Ломающий прогон ПРОВАЛИЛСЯ:');
  console.error(ошибка.message);
  process.exit(1);
}

