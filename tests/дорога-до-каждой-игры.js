console.log('\n---\n');

// N = количество плиток (реальные проверки) + 1 (за ломающий синтетический прогон)
// M = 0 (если оба прогона прошли без ошибок)
const всегоПроверок = количествоПлиток + 1;
const всегоПровалов = 0;

console.log(`Итого проверок: ${всегоПроверок}, провалов: ${всегоПровалов}`);
