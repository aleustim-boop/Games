// ============================================================================
console.log('\n---\n');
console.log('Ломающий прогон: имитируем ошибку (плитка "скоро", но файл существует)...\n');

function проверитьССинтетическойОшибкой() {
  const корень = path.join(__dirname, '..');
  const индексПуть = path.join(корень, 'index.html');
  const содержимое = fs.readFileSync(индексПуть, 'utf8');
  const плитки = собратьДанныеПлиток(содержимое);

  // Найдём первую плитку "скоро" (это домино)
  const плиткаСкоро = плитки.find(п => п.естьКлассСкоро);
  if (!плиткаСкоро) {
    throw new Error('Не найдено плитки "скоро" для синтетического теста');
  }

  console.log(`  Найдена плитка "скоро": "${плиткаСкоро.игра}"`);
  console.log(`  Теперь имитируем: как будто файл ${плиткаСкоро.игра}.html вдруг появился\n`);

  // Создаём временный объект с "фальшивыми" данными о файлах
  // Проверяем, что наша функция это ловит

  // Модифицируем логику проверки для синтетического теста:
  // Создаём фальшивую версию fs.existsSync
  const оригиналEsists = fs.existsSync;
  let вызовыExistsCall = [];

  try {
    fs.existsSync = function (путь) {
      const имяФайла = path.basename(путь);
      // Если проверяют файл домино.html — скажем, что он существует
      if (имяФайла === `${плиткаСкоро.игра}.html`) {
        вызовыExistsCall.push({путь, результат: true, причина: 'синтетически включили'});
        return true;
      }
      // Для остальных вернём истинный результат
      const результат = оригиналEsists(путь);
      вызовыExistsCall.push({путь, результат});
      return результат;
    };

    // Теперь запустим проверку — она должна выбросить ошибку
    проверитьДорогуДоКаждойИгры(false);

    // Если дошли сюда — значит, проверка НЕ выловила нашу синтетическую ошибку
    throw new Error(
      '✗ Синтетический тест провалился: проверка должна была выбросить ошибку, ' +
      'когда файл домино.html "существует", но этого не произошло. ' +
      'Проверка не умеет краснеть!'
    );
  } catch (ошибка) {
    if (
      ошибка.message.includes('домино') &&
      ошибка.message.includes('скоро') &&
      ошибка.message.includes('помечена')
    ) {
      // Отлично! Это именно та ошибка, которую мы ожидали
      console.log(`  ✓ Проверка выловила синтетическую ошибку (как надо):`);
      // Выведем только релевантную строку про домино из ошибки
      const строкиОшибки = ошибка.message.split('\n').filter(с => с.includes('домино'));
      console.log(`    "${строкиОшибки[0] || ошибка.message.split('\n')[2]}"`);
      return true;
    } else if (ошибка.message.includes('Синтетический тест провалился')) {
      throw ошибка;
    } else {
      // Неожиданная ошибка
      throw new Error(
        `Синтетический тест: неожиданная ошибка. ` +
        `Ожидали ошибку про домино и скоро, получили: ${ошибка.message.split('\n')[0]}`
      );
    }
  } finally {
    fs.existsSync = оригиналEsists;
  }
}

try {
  проверитьССинтетическойОшибкой();
  console.log('\n✓ Ломающий прогон ПРОШЁЛ: проверка умеет краснеть на синтетической ошибке.');
} catch (ошибка) {
  console.error('✗ Ломающий прогон ПРОВАЛИЛСЯ:');
  console.error(ошибка.message);
  process.exit(1);
}

// ============================================================================
