'use strict';

/* =====================================================================
   СТОРОЖ ОБЩИХ ИМЁН: страница шашек одевается чужим файлом.

   ЧТО ЗА СВЯЗЬ. Двадцать пять узлов на странице шашек названы теми же
   именами, что у дурака, и вид им даёт только style.css. Часть из них
   обязана так называться: их ищет общий js/сеть.js — он один на обе игры
   и знает страницу по именам («кнопка-создать-игру», «поле-кода» и
   прочие). Остальные просто одеты общими правилами, потому что правила
   и правда общие: кнопка есть кнопка.

   ЧЕМ ЭТО ОПАСНО. Связь была скрытой: переименует оформитель имя у
   дурака — у шашек молча слетит вид, а искать причину будут в шашках.
   Хуже того, для имён из первой группы слетит не вид, а сама игра по
   сети: js/сеть.js не найдёт узел и перестанет работать.

   ЧТО ДЕЛАЕТ ЭТА ПРОВЕРКА. Смотрит, что каждое общее имя со страницы
   шашек по-прежнему описано в style.css (или уже переехало в
   style-шашки.css — тогда связи больше нет, и это хорошо). Пропало
   и там и там — проверка краснеет и называет имя. Связь перестаёт быть
   скрытой: её нарушение видно сразу и там, где оно случилось.

   Запуск: node tests/общие-имена-шашек.js
   Выход 0 — всё на месте.
   ===================================================================== */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const страница = fs.readFileSync(path.join(КОРЕНЬ, 'шашки.html'), 'utf8');
const общий = fs.readFileSync(path.join(КОРЕНЬ, 'style.css'), 'utf8');
const свой = fs.readFileSync(path.join(КОРЕНЬ, 'style-шашки.css'), 'utf8');

/* Имена, которые ищет общий js/сеть.js. Эти трогать нельзя никому:
   от них зависит не вид, а работа игры по сети. Список взят из самого
   файла — там он объявлен ПРИЗНАКИ_РАЗМЕТКИ и разбросан по «накнопку». */
const ИМЕНА_СЕТИ = [
  'экран-друга', 'экран-комнаты', 'экран-входа',
  'кнопка-создать-игру', 'кнопка-войти-по-коду', 'кнопка-войти',
  'кнопка-копировать-код', 'кнопка-позвать-друга', 'кнопка-вернуться-в-игру',
  'кнопка-проверить-адрес', 'поле-кода', 'код-комнаты',
  'нет-сервера-главное', 'строка-связи'
];

let плохо = 0;
let проверено = 0;

console.log('=== Общие имена страницы шашек ===\n');

const имена = [...страница.matchAll(/id="([^"]+)"/g)].map(м => м[1]);
const общиеИмена = [];

for (const имя of имена) {
  const вОбщем = общий.includes('#' + имя);
  const вСвоём = свой.includes('#' + имя);
  if (!вОбщем && !вСвоём) continue;      // имя одето классами — не наш случай
  if (!вОбщем) continue;                 // вид уже свой: связи нет
  общиеИмена.push({ имя, вСвоём, сеть: ИМЕНА_СЕТИ.indexOf(имя) !== -1 });
}

console.log('имён, чей вид приходит из style.css: ' + общиеИмена.length);
for (const запись of общиеИмена) {
  проверено++;
  const пометка = запись.сеть ? ' (нужно js/сеть.js — переименованию не подлежит)' : '';
  console.log('  · ' + запись.имя + пометка + (запись.вСвоём ? ' — есть и в style-шашки.css' : ''));
}

console.log('\nПроверяем, что ни одно из них не пропало из обоих файлов оформления.');
for (const запись of общиеИмена) {
  if (!общий.includes('#' + запись.имя) && !свой.includes('#' + запись.имя)) {
    плохо++;
    console.log('  ПЛОХО: «' + запись.имя + '» больше не описан нигде — вид слетел');
  }
}

/* Отдельно: имена, которые нужны js/сеть.js, обязаны быть на странице.
   Их пропажа ломает не вид, а саму игру по сети. */
for (const имя of ИМЕНА_СЕТИ) {
  проверено++;
  if (!страница.includes('id="' + имя + '"')) {
    плохо++;
    console.log('  ПЛОХО: на странице шашек нет узла «' + имя + '», а его ищет js/сеть.js');
  }
}

console.log('\n----------------------------------------');
console.log('Проверено имён: ' + проверено);
console.log(плохо === 0
  ? 'Все общие имена на месте: вид не слетел, сеть найдёт свои узлы.'
  : 'БЕД: ' + плохо);
process.exit(плохо === 0 ? 0 : 1);
