// Проверка «подключения не ведут в пустоту» (node, без браузера).
//
// Зачем: после раскладки проекта по папкам игр одна забытая ссылка — и страница
// молча остаётся без скрипта или оформления, а сервер комнат не поднимается.
// Проверка читает сами файлы и смотрит, что всё названное в них лежит на диске:
//   1. страницы (html в корне, в игры/*/ и в rules/**) — каждый местный script src и link href;
//   2. оформление (css в корне, общее/**, игры/**) — каждый местный url() и @import;
//   3. server/ и bot/ — каждый require с относительным путём.
// Ноль найденных страниц или подключений — провал: значит, проверка ослепла.
//
// Запуск:            node tests/подключения-не-в-пустоту.js
// На копии проекта:  node tests/подключения-не-в-пустоту.js --корень=<папка копии>
// Ломающий запуск:   в КОПИИ убрать любой подключённый файл — проверка обязана покраснеть.
//
// Функцию «проверить» зовёт и программа переезда (штаб/скрипты/переезд-по-папкам.js):
// ей она отдаёт своё «воображаемое» дерево файлов, чтобы проверить переезд всухую.

'use strict';
const fs = require('fs');
const path = require('path');

/** Настоящий диск: пути всегда от корня проекта и через прямой слэш. */
function дискПроекта(корень) {
  const полный = (отн) => path.join(корень, отн);
  return {
    есть: (отн) => fs.existsSync(полный(отн)),
    читать: (отн) => fs.readFileSync(полный(отн), 'utf8'),
    список: (отн) => {
      if (!fs.existsSync(полный(отн))) return [];
      return fs.readdirSync(полный(отн), { withFileTypes: true }).map((з) => {
        // Соединение папок (img в копии) withFileTypes папкой не считает — спрашиваем диск.
        let папка = з.isDirectory();
        if (!папка && з.isSymbolicLink()) {
          try { папка = fs.statSync(полный(отн + '/' + з.name)).isDirectory(); } catch (e) { папка = false; }
        }
        return { имя: з.name, папка };
      });
    },
  };
}

const ПРОПУСКАТЬ_ПАПКИ = new Set(['node_modules', 'данные', 'снимки', '.git']);

/** Все файлы папки с нужным окончанием; вглубь — только если попросили. */
function собрать(фс, папка, окончание, вглубь) {
  const найдено = [];
  for (const з of фс.список(папка)) {
    const путь = папка ? папка + '/' + з.имя : з.имя;
    if (з.папка) {
      if (вглубь && !ПРОПУСКАТЬ_ПАПКИ.has(з.имя)) найдено.push(...собрать(фс, путь, окончание, true));
    } else if (з.имя.endsWith(окончание)) {
      найдено.push(путь);
    }
  }
  return найдено;
}

/** Заменяет куски (комментарии) пробелами той же длины: номера строк остаются верными. */
function закрасить(текст, образец) {
  return текст.replace(образец, (кусок) => кусок.replace(/[^\n]/g, ' '));
}

function номерСтроки(текст, место) {
  let н = 1;
  for (let i = 0; i < место; i++) if (текст.charCodeAt(i) === 10) н++;
  return н;
}

/** Ссылка наружу или не на файл — такие не проверяем. */
function неФайл(адрес) {
  return !адрес
    // «%23…» — это «#…» внутри картинки, вписанной в css через data: (ссылка на её же узел)
    || /^(https?:|\/\/|data:|blob:|about:|tg:|mailto:|javascript:|#|%23)/i.test(адрес)
    || адрес.includes('${') || адрес.includes('{{');
}

/** Куда ведёт адрес, записанный в файле «откуда» (путь от корня). */
function кудаВедёт(откуда, адрес) {
  let чистый = адрес.split('#')[0].split('?')[0];
  try { чистый = decodeURIComponent(чистый); } catch (e) { /* оставляем как есть */ }
  if (чистый.startsWith('/')) return path.posix.normalize(чистый.slice(1));
  return path.posix.normalize(path.posix.join(path.posix.dirname(откуда), чистый));
}

function проверить(фс) {
  const дыры = [];
  const счёт = { страниц: 0, подключенийСтраниц: 0, файловОформления: 0, ссылокОформления: 0, файловСервера: 0, require: 0 };

  // 1. Страницы.
  const страницы = [
    ...собрать(фс, '', '.html', false),
    ...фс.список('игры').filter((з) => з.папка).flatMap((з) => собрать(фс, 'игры/' + з.имя, '.html', false)),
    ...собрать(фс, 'rules', '.html', true),
  ];
  for (const страница of страницы) {
    счёт.страниц++;
    const текст = закрасить(фс.читать(страница), /<!--[\s\S]*?-->/g);
    const теги = /<(script|link)\b[^>]*?\s(?:src|href)\s*=\s*(["'])([^"']*)\2/gi;
    let м;
    while ((м = теги.exec(текст))) {
      const тег = м[1].toLowerCase();
      // у script адрес — src, у link — href; чужую пару (script href) не берём
      if (тег === 'script' && !/\ssrc\s*=/i.test(м[0])) continue;
      if (тег === 'link' && !/\shref\s*=/i.test(м[0])) continue;
      const адрес = м[3].trim();
      if (неФайл(адрес)) continue;
      счёт.подключенийСтраниц++;
      const цель = кудаВедёт(страница, адрес);
      if (!фс.есть(цель)) дыры.push({ файл: страница, строка: номерСтроки(текст, м.index), что: 'подключение страницы', адрес, ищем: цель });
    }
  }

  // 2. Оформление.
  const оформление = [
    ...собрать(фс, '', '.css', false),
    ...собрать(фс, 'общее', '.css', true),
    ...собрать(фс, 'игры', '.css', true),
  ];
  for (const файл of оформление) {
    счёт.файловОформления++;
    const текст = закрасить(фс.читать(файл), /\/\*[\s\S]*?\*\//g);
    const ссылки = /url\(\s*(["']?)([^"')]*)\1\s*\)|@import\s+(["'])([^"']*)\3/gi;
    let м;
    while ((м = ссылки.exec(текст))) {
      const адрес = (м[2] !== undefined ? м[2] : м[4]).trim();
      if (неФайл(адрес)) continue;
      счёт.ссылокОформления++;
      const цель = кудаВедёт(файл, адрес);
      if (!фс.есть(цель)) дыры.push({ файл, строка: номерСтроки(текст, м.index), что: м[2] !== undefined ? 'url() в оформлении' : '@import', адрес, ищем: цель });
    }
  }

  // 3. Сервер и бот.
  const серверные = [...собрать(фс, 'server', '.js', true), ...собрать(фс, 'bot', '.js', true)];
  for (const файл of серверные) {
    счёт.файловСервера++;
    const текст = фс.читать(файл);
    const запросы = /\brequire\(\s*(["'])(\.{1,2}\/[^"']*)\1\s*\)/g;
    let м;
    while ((м = запросы.exec(текст))) {
      // require в строчном комментарии — пример, а не подключение
      const началоСтроки = текст.lastIndexOf('\n', м.index) + 1;
      // и в подсказке «node -e "require(…)"» внутри описания файла — тоже
      if (/(^|\s)\/\/|^\s*\*|node -e/.test(текст.slice(началоСтроки, м.index))) continue;
      счёт.require++;
      const цель = path.posix.normalize(path.posix.join(path.posix.dirname(файл), м[2]));
      const годится = [цель, цель + '.js', цель + '.json', цель + '/index.js'].some((п) => фс.есть(п));
      if (!годится) дыры.push({ файл, строка: номерСтроки(текст, м.index), что: 'require', адрес: м[2], ищем: цель });
    }
  }

  // Ноль найденного — провал, а не пропуск.
  const слепота = [];
  if (!счёт.страниц) слепота.push('не найдено ни одной страницы');
  if (!счёт.подключенийСтраниц) слепота.push('на страницах не найдено ни одного подключения');
  if (!счёт.файловОформления) слепота.push('не найдено ни одного файла оформления');
  if (!счёт.ссылокОформления) слепота.push('в оформлении не найдено ни одного url() или @import');
  if (!счёт.файловСервера) слепота.push('не найдено ни одного файла сервера и бота');
  if (!счёт.require) слепота.push('в сервере и боте не найдено ни одного require');

  return { счёт, дыры, слепота, зелёная: дыры.length === 0 && слепота.length === 0 };
}

function напечатать(итог) {
  const с = итог.счёт;
  console.log(`Страниц: ${с.страниц}, подключений на них: ${с.подключенийСтраниц}`);
  console.log(`Файлов оформления: ${с.файловОформления}, url() и @import в них: ${с.ссылокОформления}`);
  console.log(`Файлов сервера и бота: ${с.файловСервера}, require с относительным путём: ${с.require}`);
  for (const с2 of итог.слепота) console.log('ПРОВАЛ (проверка ослепла): ' + с2);
  for (const д of итог.дыры) console.log(`ПРОВАЛ: ${д.файл}:${д.строка} — ${д.что} «${д.адрес}» ведёт в пустоту (нет файла ${д.ищем})`);
  const проверок = с.подключенийСтраниц + с.ссылокОформления + с.require;
  console.log(`Итого проверок: ${проверок}, провалов: ${итог.дыры.length + итог.слепота.length}`);
}

module.exports = { проверить, дискПроекта };

if (require.main === module) {
  const довод = process.argv.find((д) => д.startsWith('--корень='));
  const корень = довод ? path.resolve(довод.slice('--корень='.length)) : path.join(__dirname, '..');
  if (!fs.existsSync(корень)) {
    console.log('ПРОВАЛ: нет папки ' + корень);
    process.exit(1);
  }
  const итог = проверить(дискПроекта(корень));
  напечатать(итог);
  process.exit(итог.зелёная ? 0 : 1);
}
