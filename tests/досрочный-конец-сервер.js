function партияИдёт(комната) {
  return комната.этап === 'игра' && Boolean(комната.партия) && !комната.партия.завершена;
}

/**
 * Любой законный ход деберца за того, чья очередь, — через дверь комнаты,
 * как ходит живой игрок (так растёт его счёт ходов в партии).
 */
function ходДеберца(комната, кто) {
  const п = комната.партия;
  const и = п.игра;
  const игрок = п.игроки.indexOf(кто);
  let намерение;
  if (и.фаза === 'торговля') {
    намерение = { действие: 'торг', масть: ПравилаДеберца.обязанВыбрать(и) ? ПравилаДеберца.вариантыКозыря(и)[0] : null };
  } else if (и.фаза === 'игра') {
    намерение = { действие: 'карта', id: ПравилаДеберца.доступные(и, игрок)[0].id };
  } else {
    намерение = { действие: и.фаза === 'взятка' ? 'взятка' : 'раздача' };
  }
  return комнаты.сделатьХод(комната, кто, намерение);
}

/** Ходить за людей деберца, пока «кто» не сделает свой первый ход. */
function деберцДоХода(комната, кто) {
  for (let шаг = 0; шаг < 40; шаг++) {
    if ((комната.игроки[кто].ходовВПартии || 0) > 0) return true;
    const ходит = комната.партия.игроки[комната.партия.игра.ход];
    const игрок = комната.игроки[ходит];
    if (!игрок || игрок.этоБот) return false;
    if (!ходДеберца(комната, ходит).принято) return false;
  }
  return false;
}

/** Пустой будильник, который не держит программу: чтобы было что гасить. */
function пустойБудильник() {
  const т = setTimeout(function () {}, 10 * 60 * 1000);
  if (т.unref) т.unref();
  return т;
}

/**
 * A сходил и вышел, B, C, D согласились. Проверяем рейтинг: у A поражение,
 * оставшимся — ничего. Общий ход для личного стола и для стола парами.
 */
function ушёлИТроеСогласились(стол, сНапарником) {
  const к = стол.комната;
  const м = стол.места;
  const н = стол.номера;
  проверить(деберцДоХода(к, м.A), 'A сделал свой ход');
  комнаты.выйти(к, м.A);
  проверить(к.игроки[м.A].сдался === true && к.игроки[м.A].этоБот === true, 'A ушёл: «сдался», место водит бот');
  проверить(партияИдёт(к), 'партия идёт после ухода A');

  const голосA = голос(к, м.A, true);
  проверить(голосA.принято === false, 'ушедший A не голосует');

  const до = { A: следВРейтинге('деберц', н.A), B: следВРейтинге('деберц', н.B),
               C: следВРейтинге('деберц', н.C), D: следВРейтинге('деберц', н.D) };
  const рейтингДо = вызовыРейтинга.length;
  предложить(к, м.B);
  голос(к, м.C, true);
  проверить(партияИдёт(к), 'два «за» из трёх людей — партия идёт (порог 3)');

  /* Будильники: если настоящих сейчас нет, заводим пустые — после конца
     партии не должно остаться ни одного. */
  if (!к.таймерБота) к.таймерБота = пустойБудильник();
  if (!к.таймерПросрочки) к.таймерПросрочки = пустойБудильник();

  голос(к, м.D, true);
  проверить(к.этап === 'конец' && к.партия.завершена === true, 'три «за» из трёх — партия закончена');
  проверить(!к.таймерБота, 'будильник бота погашен после конца по согласию');
  проверить(!к.таймерПросрочки, 'будильник просрочки погашен после конца по согласию');
  проверить(typeof к.партия.результат === 'string', 'результат — строка (есть проигравший)');
  проверить(Array.isArray(к.партия.проигравшие) && к.партия.проигравшие.length === 1 && к.партия.проигравшие[0] === м.A,
            'проигравший — ровно A');
  проверить(вызовыРейтинга.length === рейтингДо + 1, 'рейтинг зван один раз');

  const вызов = вызовыРейтинга[рейтингДо];
  const записьA = вызов ? вызов.застолье.find(function (з) { return з.номер === н.A; }) : null;
  проверить(Boolean(записьA) && записьA.этоБот === false, 'A в застолье для рейтинга — человек (этоБот:false)');
  проверить(Boolean(записьA) && записьA.победил === false && записьA.внеСчёта !== true, 'у A в застолье поражение и он в счёте');

  const послеA = следВРейтинге('деберц', н.A);
  const партийA = до.A.я ? до.A.я.партий : 0;
  const победA = до.A.я ? до.A.я.побед : 0;
  проверить(Boolean(послеA.я) && послеA.я.партий === партийA + 1 && послеA.я.побед === победA,
            'A в рейтинге: партия +1, побед не прибавилось (поражение)');

  for (const кто of ['B', 'C', 'D']) {
    const после = следВРейтинге('деберц', н[кто]);
    проверить(JSON.stringify(после.я) === JSON.stringify(до[кто].я),
              кто + ' ничего не получил: очки, партии и победы как были (' + JSON.stringify(после.я) + ')');
    проверить(JSON.stringify(после.сила) === JSON.stringify(до[кто].сила), кто + ': сила не изменилась');
    const запись = вызов ? вызов.застолье.find(function (з) { return з.номер === н[кто]; }) : null;
    проверить(Boolean(запись) && запись.победил === false && запись.ничья === false,
              кто + ' в застолье без победы и без ничьей');
  }

  if (сНапарником) {
    const номерНапарника = записьA ? записьA.напарник : null;
    проверить(записьA && записьA.парами === true, 'стол и правда парами');
    проверить([н.B, н.C, н.D].indexOf(номерНапарника) !== -1, 'у A нашёлся живой напарник: ' + номерНапарника);
    const ключНапарника = ['B', 'C', 'D'].find(function (кто) { return н[кто] === номерНапарника; });
    const после = ключНапарника ? следВРейтинге('деберц', номерНапарника) : null;
    проверить(Boolean(ключНапарника) && JSON.stringify(после.я) === JSON.stringify(до[ключНапарника].я),
              'напарник ушедшего ничего не получил и ничего не потерял');
  }
}

