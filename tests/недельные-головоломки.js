'use strict';
const assert = require('node:assert/strict');
const fs = require('fs');
const os = require('os');
const path = require('path');
const vm = require('vm');
process.env.ДАННЫЕ_ИГРЫ = fs.mkdtempSync(path.join(os.tmpdir(), 'weekly-puzzle-'));
const файл = require.resolve('../server/лучший-счёт');
const исходник = fs.readFileSync(файл, 'utf8');
function модуль(код) {
  const среда = { module: { exports: {} }, require: require('module').createRequire(файл), process, console, Buffer };
  vm.runInNewContext(код, среда);
  return среда.module.exports;
}
function проверить(код) {
  const счёт = модуль(код);
  счёт.забытьВсё();
  const воскресенье = new Date(2026, 9, 4, 12).getTime();
  const понедельник = new Date(2026, 9, 5, 12).getTime();
  function сыграть(номер, игра, режим, значение, время) {
    const билет = счёт.выдатьБилет(номер, игра, режим, время);
    assert.equal(билет.ок, true);
    const ответ = счёт.принять(номер, билет.билет, значение, 'Участник ' + номер, время + 300000);
    assert.equal(ответ.ок, true, JSON.stringify(ответ));
    assert.equal(счёт.принять(номер, билет.билет, значение, 'Повтор', время + 310000).ок, false);
    return ответ;
  }
  const таблицы = время => JSON.parse(JSON.stringify(счёт.публичныеЛидерыНедели(время)));
  const классика = время => таблицы(время).find(т => т.метка === '2048-classic').лидеры;
  сыграть(920101, '2048', 'classic', { счёт: 9000 }, воскресенье);
  assert.equal(классика(воскресенье).length, 1);
  assert.equal(классика(понедельник).length, 0, 'новая неделя не наследует старый рекорд');
  const повтор = сыграть(920101, '2048', 'classic', { счёт: 1000 }, понедельник);
  assert.equal(повтор.значение, 9000, 'общий рекорд сохранён');
  assert.equal(повтор.улучшение, false);
  сыграть(920102, '2048', 'classic', { счёт: 2000 }, понедельник);
  assert.deepEqual(классика(понедельник).map(л => л.имя), ['Участник 920102', 'Участник 920101'], 'нерекордная попытка вошла в неделю со своим счётом');
  сыграть(920101, '2048', 'classic', { счёт: 500 }, понедельник + 600000);
  assert.equal(классика(понедельник)[0].имя, 'Участник 920102');
  сыграть(920101, '2048', 'classic', { счёт: 20000 }, понедельник + 1200000);
  assert.equal(классика(понедельник)[0].имя, 'Участник 920101', 'новый рекорд обновляет и неделю');
  сыграть(920103, 'судоку', 'easy', { секунд: 120 }, понедельник);
  сыграть(920104, 'судоку', 'easy', { секунд: 90 }, понедельник);
  const все = таблицы(понедельник);
  assert.equal(все.length, 6, 'два режима 2048 и четыре сложности судоку');
  assert.equal(все.find(т => т.метка === 'sudoku-easy').лидеры[0].имя, 'Участник 920104');
  for (const л of все.flatMap(т => т.лидеры)) assert.deepEqual(Object.keys(л).sort(), ['имя', 'место']);
  счёт.включитьЗапись();
  сыграть(920105, '2048', 'falling', { счёт: 500 }, понедельник);
  assert.deepEqual(JSON.parse(JSON.stringify(модуль(код).публичныеЛидерыНедели(понедельник))), таблицы(понедельник), 'атомарная запись и перезапуск');
}
проверить(исходник);
const порча = исходник.replace('результат.неделя = { с, значение: число };', '');
assert.notEqual(порча, исходник);
assert.throws(() => проверить(порча), 'копия без недельного учёта должна провалиться');
console.log('PASS: реальные билеты и результаты, смена недели, нерекордные попытки, лучший недельный результат, режимы, приватность, перезапуск; порча обнаружена.');
