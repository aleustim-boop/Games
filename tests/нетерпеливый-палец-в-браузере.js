/* =====================================================================
   НЕТЕРПЕЛИВЫЙ ПАЛЕЦ — может ли человек застопорить игру нажатиями.

   ЭТО НЕ АВТОПРОГОН ДЛЯ NODE. Файл вставляется в консоль браузера, когда
   игра уже открыта.

   ЗАЧЕМ. В игру добавили правило: как только человек ткнул в карту,
   которой сейчас нельзя, ход соперника отодвигается — чтобы ответ на
   нажатие успел дожить до конца, а не был стёрт чужим ходом.

   И здесь есть ловушка, ради которой этот замер и написан. Человек,
   который тычет чаще, чем длится ответ, отодвигал бы ход соперника
   бесконечно — и партия встала бы намертво: соперник не ходит, значит
   слово к человеку не возвращается, значит нажимать больше нечего.
   Разработчик говорит, что предусмотрел это: ход отодвигается ОДИН раз
   на каждое своё назначение. Проверяем не на словах.

   КАК ПРОВЕРЯЕТ. Игру доигрывает «Автоигрок» — он нажимает настоящие
   кнопки и карты, как человек. Параллельно с ним тычет «палец»: каждые
   N миллисекунд щёлкает по случайной карте руки, ни на что не глядя.
   Замер при этом считает ЗАСТОИ — сколько времени подряд на столе
   ничего не менялось В ТЕ МИГИ, КОГДА СЛОВО НЕ ЗА ЧЕЛОВЕКОМ. Пока
   слово за человеком, игра ждёт его законно, и такое ожидание в счёт
   не идёт.

   Тычки — настоящими нажатиями по узлам карт (.click()), а не вызовом
   внутренних функций: только так проба проходит через всё то же, через
   что проходит живой палец, включая глухоту руки после кнопки.

   ЧТО ЗАПУСКАТЬ (звать по одному, ответ приходит не сразу):

     нетерпеливый.прогон({ партий: 3, мсМеждуТычками: 250 })
         Три партии подряд, тыкая четыре раза в секунду.

     нетерпеливый.прогон({ партий: 2, мсМеждуТычками: 0 })
         То же, но без тычков вовсе — это «как должно быть», с чем
         сравниваем.

     нетерпеливый.дожать(20)
         Двадцать секунд ТОЛЬКО тычков, без единого законного хода:
         самый злой случай — человек тычет и не ходит. Отвечает,
         сходил ли соперник хоть раз за это время.
   ===================================================================== */

(function () {
  'use strict';

  const пауза = (мс) => new Promise((r) => setTimeout(r, мс));
  const партияИдёт = () => typeof партия !== 'undefined' && Boolean(партия) && !партия.завершена;

  /** Плашка итога на экране — партия доиграна. */
  function итогПоказан() {
    const узел = document.getElementById('экран-результата');
    return Boolean(узел && узел.classList.contains('экран--виден'));
  }

  /**
   * Слепок стола: если он не меняется, значит на столе ничего не
   * происходит. Берём только то, что двигает партию: карты на столе,
   * отбой, колода и размеры всех рук.
   */
  function слепок() {
    if (!партияИдёт()) return 'партии нет';
    const руки = Object.keys(партия.руки).sort()
      .map((и) => и + ':' + партия.руки[и].length).join(',');
    const стол = партия.стол.map(
      (п) => п.атака.имя + п.атака.масть + '/' + (п.защита ? п.защита.имя + п.защита.масть : '-')
    ).join(' ');
    return [стол, партия.отбой.length, партия.колода.length, руки,
            партия.атакует, партия.берёт].join('#');
  }

  /** Настоящее нажатие по случайной карте руки — как пальцем. */
  function ткнутьПальцем() {
    const карты = document.querySelectorAll('#карты-человека .карта');
    if (!карты.length) return false;
    карты[Math.floor(Math.random() * карты.length)].click();
    return true;
  }

  /**
   * Одна партия под тычками. Возвращает: доигралась ли, сколько тычков
   * сделано, самый долгий застой (в те миги, когда слово не за человеком)
   * и что сказал Автоигрок.
   */
  async function однаПартия(мсМеждуТычками, потолокСекунд) {
    начатьПартию();
    await пауза(600);
    Автоигрок.начать();

    let тычков = 0;
    let последнийТычок = 0;
    let прошлыйСлепок = слепок();
    let застойС = Date.now();
    let самыйДолгийЗастой = 0;
    let ходовСоперника = 0;
    const начало = Date.now();
    const крайний = начало + потолокСекунд * 1000;

    while (Date.now() < крайний) {
      await пауза(80);
      if (итогПоказан()) break;
      if (!партияИдёт()) continue;

      if (мсМеждуТычками > 0 && Date.now() - последнийТычок >= мсМеждуТычками) {
        if (ткнутьПальцем()) тычков++;
        последнийТычок = Date.now();
      }

      const сейчас = слепок();
      if (сейчас !== прошлыйСлепок) {
        прошлыйСлепок = сейчас;
        застойС = Date.now();
        ходовСоперника++;
      } else if (!сейчасМойХод()) {
        /* Слово не за человеком — ждать нечего и некого, кроме соперника.
           Считаем, сколько он не шевелится. */
        самыйДолгийЗастой = Math.max(самыйДолгийЗастой, Date.now() - застойС);
      } else {
        // Ждём человека — это законно, застоем не считаем.
        застойС = Date.now();
      }
    }

    const отчётИгрока = Автоигрок.отчёт();
    Автоигрок.стоп();
    return {
      доиграна: итогПоказан(),
      секунд: Math.round((Date.now() - начало) / 1000),
      тычков: тычков,
      измененийНаСтоле: ходовСоперника,
      самыйДолгийЗастойМс: самыйДолгийЗастой,
      итог: отчётИгрока.итог,
      поломкиАвтоигрока: отчётИгрока.поломки,
      подсказка: отчётИгрока.подсказка
    };
  }

  async function прогон(набор) {
    const н = набор || {};
    const партий = Number(н.партий) || 3;
    const мс = н.мсМеждуТычками === undefined ? 250 : Number(н.мсМеждуТычками);
    const потолок = Number(н.потолокСекунд) || 240;
    const партии = [];
    for (let i = 0; i < партий; i++) {
      партии.push(await однаПартия(мс, потолок));
      await пауза(500);
    }
    const итог = {
      тычокКаждые: мс ? мс + ' мс' : 'не тыкали вовсе',
      партий: партии.length,
      доиграно: партии.filter((п) => п.доиграна).length,
      самыйДолгийЗастойМс: Math.max(...партии.map((п) => п.самыйДолгийЗастойМс)),
      поломок: партии.reduce((с, п) => с + п.поломкиАвтоигрока.length, 0),
      партии: партии
    };
    console.log(итог);
    return итог;
  }

  /** Один законный ход за человека — чтобы слово вернулось к соперникам. */
  function сходитьЗаконно() {
    if (!партияИдёт() || !сейчасМойХод()) return false;
    рукаГлухаДо = 0;
    const текущая = фаза(партия);
    if (текущая === 'защита') {
      for (let п = 0; п < партия.стол.length; п++) {
        if (партия.стол[п].защита) continue;
        for (let к = 0; к < партия.руки.человек.length; к++) {
          if (бьёт(партия.руки.человек[к], партия.стол[п].атака, партия.козырь)) {
            отбитьсяКартой(п, к); return true;
          }
        }
      }
      нажатьБеру(); return true;
    }
    for (let к = 0; к < партия.руки.человек.length; к++) {
      if (можноПоложить(партия, партия.руки.человек[к])) { сходитьКартой(к); return true; }
    }
    if (мнеМожноЗакончитьПодход(текущая)) { нажатьБито(); return true; }
    return false;
  }

  /**
   * Самый злой случай: человек тычет без остановки, а ходит только тогда,
   * когда без него игра дальше не пойдёт. Отвечает на прямой вопрос —
   * ходит ли соперник и как долго его приходится ждать.
   */
  async function дожать(секунд, мсМеждуТычками) {
    const сколько = Number(секунд) || 20;
    const шаг = Number(мсМеждуТычками) || 120;
    if (!партияИдёт()) { начатьПартию(); await пауза(700); }
    Автоигрок.стоп();

    let тычков = 0;
    let ходовСоперника = 0;
    let своихХодов = 0;
    let прошлый = слепок();
    let последнееДвижение = Date.now();
    let самоеДолгоеОжидание = 0;
    const начало = Date.now();

    while (Date.now() - начало < сколько * 1000) {
      ткнутьПальцем(); тычков++;
      await пауза(шаг);
      const сейчас = слепок();
      if (сейчас !== прошлый) {
        прошлый = сейчас;
        последнееДвижение = Date.now();
        ходовСоперника++;
      } else if (!сейчасМойХод()) {
        самоеДолгоеОжидание = Math.max(самоеДолгоеОжидание, Date.now() - последнееДвижение);
      } else {
        последнееДвижение = Date.now();
      }
      if (!партияИдёт()) { начатьПартию(); await пауза(700); прошлый = слепок(); continue; }
      // Слово наше — ходим, иначе ждать соперника бессмысленно: ждут нас.
      if (сейчасМойХод()) {
        if (сходитьЗаконно()) своихХодов++;
        прошлый = слепок();
        последнееДвижение = Date.now();
      }
    }
    const итог = {
      тыкалиСекунд: сколько,
      тычокКаждые: шаг + ' мс',
      тычков: тычков,
      своихХодов: своихХодов,
      разСтолДвинулсяСам: ходовСоперника,
      самоеДолгоеОжиданиеСоперникаМс: самоеДолгоеОжидание,
      подсказка: (document.getElementById('подсказка-текст') || {}).textContent
    };
    console.log(итог);
    return итог;
  }

  window.нетерпеливый = { прогон, дожать, слепок };
  console.log('Замер готов. Зовите: нетерпеливый.прогон({партий:3, мсМеждуТычками:250}), ' +
              'нетерпеливый.дожать(20).');
})();
