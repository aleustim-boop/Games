'use strict';

/* Проверка общее/js/ярлык.js: считает партии и предлагает ярлык на главный экран
   вовремя, не чаще двух раз за жизнь и только там, где это можно.
   Файл гоняем в песочнице vm с поддельными localStorage, часами Date.now
   и window.Telegram.WebApp.

   Запуск:  node tests/ярлык.js [путь-к-файлу]
   (путь по умолчанию — общее/js/ярлык.js)
   Ломающий запуск: передать путь к КОПИИ файла с порогом 1 партия, или к копии
   без проверки «уже предлагали» — проверка обязана покраснеть.
   Настоящий файл не портим. */

const fs = require('fs');
const vm = require('vm');
const path = require('path');

const КОРЕНЬ = path.resolve(__dirname, '..');
const аргумент = process.argv.slice(2).find(function (а) { return !а.startsWith('--'); });
const ПУТЬ_ФАЙЛА = аргумент ? path.resolve(аргумент) : path.join(КОРЕНЬ, 'общее', 'js', 'ярлык.js');
const ИСХОДНИК = fs.readFileSync(ПУТЬ_ФАЙЛА, 'utf8');

const ДЕНЬ = 24 * 60 * 60 * 1000;

let всего = 0;
let провалов = 0;
function проверить(что, правда) {
  всего++;
  if (!правда) провалов++;
  console.log((правда ? '  ок   ' : '  БЕДА ') + что);
}

/** Собирает мир: песочница с файлом, часами, памятью и (по желанию) Telegram. */
function мир(настройки) {
  const н = Object.assign({ статус: 'missed', версияОк: true, телеграм: true, память: {} }, настройки || {});
  const м = {
    время: 1700000000000,
    вызовов: 0,
    память: н.память,
    события: {},
    окно: null,
    ошибки: []
  };
  const хранилище = {
    getItem: function (к) { return Object.prototype.hasOwnProperty.call(м.память, к) ? м.память[к] : null; },
    setItem: function (к, з) { м.память[к] = String(з); },
    removeItem: function (к) { delete м.память[к]; }
  };
  const окно = { localStorage: хранилище };
  if (н.телеграм) {
    окно.Telegram = {
      WebApp: {
        initData: 'x',
        isVersionAtLeast: function (в) { return н.версияОк; },
        checkHomeScreenStatus: function (обратно) { обратно(м.статус); },
        addToHomeScreen: function () { м.вызовов++; },
        onEvent: function (имя, обработчик) { м.события[имя] = обработчик; }
      }
    };
  }
  м.статус = н.статус;
  м.окно = окно;
  const часы = { now: function () { return м.время; } };
  const песочница = { window: окно, Date: часы, console: console };
  окно.window = окно;
  vm.createContext(песочница);
  try {
    vm.runInContext(ИСХОДНИК, песочница, { filename: ПУТЬ_ФАЙЛА });
  } catch (е) {
    м.ошибки.push(е);
  }
  м.Ярлык = окно.Ярлык;
  /** Одна партия и сразу попытка предложения; время между партиями — минута. */
  м.сыграть = function () {
    м.время += 60 * 1000;
    м.Ярлык.партияСыграна('тест');
    м.Ярлык.предложитьЕслиПора();
  };
  return м;
}

console.log('Файл: ' + ПУТЬ_ФАЙЛА);

// --- Основной ход: 2 партии — 0; 3 — один; 4-я и 5-я — по-прежнему один; +14 дней — два; ещё +14 — два.
{
  const м = мир();
  проверить('файл загрузился и дал window.Ярлык', !м.ошибки.length && !!м.Ярлык
    && typeof м.Ярлык.партияСыграна === 'function'
    && typeof м.Ярлык.предложитьЕслиПора === 'function'
    && typeof м.Ярлык.состояние === 'function');
  if (м.Ярлык) {
    м.сыграть(); м.сыграть();
    проверить('2 партии — окно не звали', м.вызовов === 0);
    м.сыграть();
    проверить('3 партии — окно позвали один раз', м.вызовов === 1);
    м.сыграть(); м.сыграть();
    проверить('4-я и 5-я — по-прежнему один вызов', м.вызовов === 1);
    м.время += 14 * ДЕНЬ;
    м.сыграть();
    проверить('через 14 дней — второй вызов', м.вызовов === 2);
    м.время += 14 * ДЕНЬ;
    м.сыграть();
    проверить('ещё через 14 дней — всё равно два (больше двух не бывает)', м.вызовов === 2);
    const с = м.Ярлык.состояние();
    проверить('состояние(): offers=2, played=7, added=false',
      с.offers === 2 && с.played === 7&& с.added === false);
    с.played = 999;
    проверить('состояние() отдаёт копию, а не саму запись', м.Ярлык.состояние().played === 7);
  }
}

// --- Раньше 14 дней второе предложение не уходит.
{
  const м = мир();
  м.сыграть(); м.сыграть(); м.сыграть();
  м.время += 13 * ДЕНЬ;
  м.сыграть();
  проверить('через 13 дней — второго вызова ещё нет', м.вызовов === 1);
}

// --- Статусы, при которых не предлагаем.
['added', 'unsupported', 'unknown'].forEach(function (статус) {
  const м = мир({ статус: статус });
  м.сыграть(); м.сыграть(); м.сыграть(); м.сыграть();
  проверить('статус «' + статус + '» — 0 вызовов', м.вызовов === 0);
});

// --- Старая версия Telegram.
{
  const м = мир({ версияОк: false });
  м.сыграть(); м.сыграть(); м.сыграть(); м.сыграть();
  проверить('версия ниже 8.0 — 0 вызовов', м.вызовов === 0);
}

// --- Нет Telegram вовсе: без исключений и без вызовов.
{
  const м = мир({ телеграм: false });
  let упало = false;
  try {
    м.сыграть(); м.сыграть(); м.сыграть(); м.сыграть();
    м.Ярлык.состояние();
  } catch (е) { упало = true; }
  проверить('нет Telegram — без исключений', !упало && !м.ошибки.length);
  проверить('нет Telegram — счётчик всё равно растёт', м.Ярлык.состояние().played === 4);
}

// --- Две отметки за 10 секунд — одна партия.
{
  const м = мир();
  м.Ярлык.партияСыграна('а');
  м.время += 10 * 1000;
  м.Ярлык.партияСыграна('б');
  проверить('две отметки за 10 с — счётчик +1', м.Ярлык.состояние().played === 1);
  м.время += 31 * 1000;
  м.Ярлык.партияСыграна('в');
  проверить('отметка через 30+ с — снова +1', м.Ярлык.состояние().played === 2);
}

// --- Событие homeScreenAdded: больше никогда.
{
  const м = мир();
  проверить('подписка на homeScreenAdded сделана', typeof м.события.homeScreenAdded === 'function');
  if (typeof м.события.homeScreenAdded === 'function') {
    м.события.homeScreenAdded();
    проверить('после события added=true', м.Ярлык.состояние().added === true);
    м.сыграть(); м.сыграть(); м.сыграть(); м.сыграть();
    м.время += 30 * ДЕНЬ;
    м.сыграть();
    проверить('после homeScreenAdded — 0 вызовов, даже через месяц', м.вызовов === 0);
  }
}

// --- Испорченная память не роняет.
['{не json', 'null', '"строка"', '{"played":"много","offers":-5,"lastOffer":null,"added":1}'].forEach(function (мусор) {
  const м = мир({ память: { home_shortcut: мусор } });
  let упало = false;
  try {
    м.сыграть(); м.сыграть(); м.сыграть();
  } catch (е) { упало = true; }
  проверить('испорченная память ' + JSON.stringify(мусор) + ' — не падает, считает с нуля',
    !упало && !м.ошибки.length && м.Ярлык.состояние().played === 3 && м.вызовов === 1);
});

// --- Память, которая бросает исключения.
{
  const м = мир();
  м.окно.localStorage.getItem = function () { throw new Error('нет доступа'); };
  м.окно.localStorage.setItem = function () { throw new Error('нет доступа'); };
  let упало = false;
  try { м.сыграть(); м.сыграть(); м.сыграть(); м.Ярлык.состояние(); } catch (е) { упало = true; }
  проверить('память бросает исключения — файл не падает', !упало);
}

// --- Запись лежит под нужным ключом и в нужном виде.
{
  const м = мир();
  м.сыграть();
  const сырое = м.память.home_shortcut;
  let запись = null;
  try { запись = JSON.parse(сырое); } catch (е) { /* останется null */ }
  проверить('запись под ключом home_shortcut с полями played/offers/lastOffer/added',
    !!запись && запись.played === 1 && запись.offers === 0 && запись.lastOffer === 0 && запись.added === false);
}

console.log('\nПроверок: ' + всего + ', провалов: ' + провалов);
process.exit(провалов ? 1 : 0);
