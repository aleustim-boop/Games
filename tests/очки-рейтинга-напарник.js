/* =====================================================================
   ОЧКИ РЕЙТИНГА: ПОЛЕ НАПАРНИК И НАЧИСЛЕНИЯ В ИГРЕ 2 НА 2

   Что проверяем. В функции учестьПартию (server/рейтинг.js) около строки 548-549
   каждый победитель/ничейник получает очки за других игроков за столом, но если
   другой игрок является напарником (поле игрок.напарник), то цена умножается на 0.5.
   За настоящих соперников цена не меняется.

   Цена партии (из ЦЕНА.человек):
     - победа: 10
     - ничья: 5
     - поражение: 0

   Проверяем три сценария:
     1) Партия 2 на 2, пара победила, другая проиграла:
        победитель должен получить 10 (за 1-го соперника) + 10 (за 2-го соперника)
        + 5 (за напарника = 10 × 0.5) = 25 очков, проигравший — 0

     2) Партия 2 на 2, все ничья:
        каждый ничейник должен получить 5 (1-й соперник) + 5 (2-й соперник)
        + 2.5 (за напарника = 5 × 0.5) = 12.5 очков (дробное число!)

     3) Обычная партия 1 на 1 БЕЗ поля напарник: цена должна остаться прежней
        (победитель 10, проигравший 0), никакого умножения на 0.5

   Как проверить, что тест краснеет:
     Если в коде учестьПартию будет считать напарника обычным соперником
     (без умножения на 0.5), то:
       - Тест 1 провалится: 101 получит 10 + 10 + 10 = 30 вместо 25
       - Тест 2 провалится: 101 получит 5 + 5 + 5 = 15 вместо 12.5
     Если убрать проверку на напарника вовсе (всегда цена × 1):
       - Тесты 1 и 2 всё равно покраснеют
       - Тест 3 останется зелёным, т.к. там нет напарников

   Боевых данных не касается: папка данных (GAMES_DATA) на время прогона уводится
   во временную. Как в tests/очки-рейтинга.js.

   Запуск: node tests/очки-рейтинга-напарник.js
   Выход 0 — провалов нет.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

process.env.GAMES_DATA = fs.mkdtempSync(path.join(os.tmpdir(), 'очки-рейтинга-напарник-'));

const КОРЕНЬ = path.join(__dirname, '..');
const рейтинг = require(path.join(КОРЕНЬ, 'server', 'рейтинг.js'));

let ошибок = 0;

function равно(что, было, надо) {
  const ок = было === надо;
  if (!ок) ошибок++;
  console.log((ок ? '  ✓' : '  ✗') + ' ' + что + ': ' + было + (ок ? '' : ' (ждали ' + надо + ')'));
}

/** Живой игрок за столом. Исход — 'победа', 'ничья' или 'поражение'. */
function человек(номер, исход, напарник) {
  return {
    номер: номер, имя: 'Т' + номер, этоБот: false,
    победил: исход === 'победа', ничья: исход === 'ничья',
    напарник: напарник === undefined ? null : напарник
  };
}

/** Сколько очков у игрока в этой игре сейчас. */
function очки(номер, игра) {
  const срез = рейтинг.срезДляИгрока(игра || 'дурак', номер);
  return срез.я ? срез.я.очки : 0;
}

console.log('=== Очки рейтинга: напарник в игре 2 на 2 ===\n');

console.log('1. Партия 2 на 2: пара (101, 103) победила, пара (102, 104) проиграла');
console.log('   101 должен получить 10 (за 102) + 10 (за 104) + 5 (за 103, напарник) = 25');
рейтинг.забытьВсё();
рейтинг.учестьПартию('дурак', [
  человек(101, 'победа', 103),
  человек(102, 'поражение', 104),
  человек(103, 'победа', 101),
  человек(104, 'поражение', 102)
]);
равно('игрок 101 (победитель с напарником)', очки(101), 25);
равно('игрок 103 (напарник 101, тоже победитель)', очки(103), 25);
равно('игрок 102 (проигравший, поражение не платят)', очки(102), 0);
равно('игрок 104 (проигравший, поражение не платят)', очки(104), 0);

console.log('\n2. Партия 2 на 2: все четверо сыграли вничью');
console.log('   Каждый должен получить 5 + 5 + 2.5 = 12.5 (дробное число!)');
рейтинг.забытьВсё();
рейтинг.учестьПартию('дурак', [
  человек(201, 'ничья', 203),
  человек(202, 'ничья', 204),
  человек(203, 'ничья', 201),
  человек(204, 'ничья', 202)
]);
равно('игрок 201 (ничья с напарником)', очки(201), 12.5);
равно('игрок 202 (ничья с напарником)', очки(202), 12.5);
равно('игрок 203 (ничья, напарник 201)', очки(203), 12.5);
равно('игрок 204 (ничья, напарник 202)', очки(204), 12.5);

console.log('\n3. Обычная партия 1 на 1 без напарников (обратная совместимость)');
console.log('   Победитель 10, проигравший 0, ничего не изменилось');
рейтинг.забытьВсё();
рейтинг.учестьПартию('дурак', [
  человек(301, 'победа'),
  человек(302, 'поражение')
]);
равно('победитель без напарника', очки(301), 10);
равно('проигравший без напарника', очки(302), 0);

console.log('\n4. Партия 2 на 2: одна пара побеждает, но разный исход внутри пары');
console.log('   (нужно убедиться, что исход каждого считается независимо)');
рейтинг.забытьВсё();
рейтинг.учестьПартию('дурак', [
  человек(401, 'победа', 403),   // Победитель с напарником
  человек(402, 'поражение', 404), // Проигравший с напарником
  человек(403, 'ничья', 401),     // Ничейник (напарник 401)
  человек(404, 'ничья', 402)      // Ничейник (напарник 402)
]);
// 401: победа против 402 (10) + против 404 (10) + против напарника 403 победа (10 × 0.5 = 5) = 25
равно('401: победитель', очки(401), 25);
// 403: ничья против 401 (5) + против 402 (5) + против напарника 401 ничья (5 × 0.5 = 2.5) = 12.5
равно('403: ничейник', очки(403), 12.5);
// 402: поражение — всегда 0
равно('402: проигравший', очки(402), 0);
// 404: ничья против 401 (5) + против 403 (5) + против напарника 402 ничья (5 × 0.5 = 2.5) = 12.5
равно('404: ничейник', очки(404), 12.5);

console.log('\n5. Партия 2 на 2 с ничьей одной стороны и победой другой');
рейтинг.забытьВсё();
рейтинг.учестьПартию('дурак', [
  человек(501, 'ничья', 503),
  человек(502, 'ничья', 504),
  человек(503, 'победа', 501),
  человек(504, 'победа', 502)
]);
// 501: ничья против 502 (5) + против 504 (5) + против напарника 503 ничья (5 × 0.5 = 2.5) = 12.5
равно('501: ничейник против пары, которая победила', очки(501), 12.5);
// 503: победа против 502 (10) + против 504 (10) + против напарника 501 победа (10 × 0.5 = 5) = 25
равно('503: победитель', очки(503), 25);

console.log('\n----------------------------------------');
console.log('Итого проверок: 17, провалов: ' + ошибок);
process.exit(ошибок ? 1 : 0);
