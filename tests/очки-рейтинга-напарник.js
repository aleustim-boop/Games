равно(партийВместе + ' поражений вместе: за напарника 0', заПоражения, 0);
const одинНаОдин = рейтинг.учестьПартию('дурак', [человек(801, 'победа'), человек(803, 'поражение')]);
равно('потом 801 обыграл бывшего напарника 803 один на один — полная цена', одинНаОдин[801], ЗА_ЧЕЛОВЕКА.победа);

