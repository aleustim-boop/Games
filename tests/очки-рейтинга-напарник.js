/* =====================================================================
   ОЧКИ РЕЙТИНГА: ПОЛЕ НАПАРНИК И НАЧИСЛЕНИЯ В ИГРЕ 2 НА 2

   Что проверяем. В функции учестьПартию (server/рейтинг.js) около строк 1011-1022
   каждый победитель/ничейник получает очки за других игроков за столом, но если
   другой игрок является напарником (поле игрок.напарник), то цена умножается на 0.5.
   За настоящих соперников цена не меняется. С 30.09 победителю платят только за
   обыгранных (исход хуже) — это видно в сценарии 5; подробно проверяет
   tests/рейтинг-очки-только-за-обыгранных.js.

   Цена партии (из ЦЕНА.человек):
     - победа: 10
     - ничья: 5
     - поражение: 0

   Проверяем три сценария:
     1) Партия 2 на 2, пара победила, другая проиграла:
        победитель должен получить 10 (за 1-го соперника) + 10 (за 2-го соперника)
        + 5 (за напарника = 10 × 0.5) = 25 очков, проигравший — 0

     2) Партия 2 на 2, все ничья:
        каждый ничейник должен получить 5 (1-й соперник) + 5 (2-й соперник)
        + 2.5 (за напарника = 5 × 0.5) → 12 очков (очки за напарника округляются вниз)

     3) Обычная партия 1 на 1 БЕЗ поля напарник: цена должна остаться прежней
        (победитель 10, проигравший 0), никакого умножения на 0.5

   Как проверить, что тест краснеет:
     Если в коде учестьПартию будет считать напарника обычным соперником
     (без умножения на 0.5), то:
       - Тест 1 провалится: 101 получит 10 + 10 + 10 = 30 вместо 25
       - Тест 2 провалится: 101 получит 5 + 5 + 5 = 15 вместо 12.5
     Если убрать проверку на напарника вовсе (всегда цена × 1):
       - Тесты 1 и 2 всё равно покраснеют
       - Тест 3 останется зелёным, т.к. там нет напарников

   Боевых данных не касается: папка данных (GAMES_DATA) на время прогона уводится
   во временную. Как в tests/очки-рейтинга.js.

   Запуск: node tests/очки-рейтинга-напарник.js
   Выход 0 — провалов нет.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

process.env.GAMES_DATA = fs.mkdtempSync(path.join(os.tmpdir(), 'очки-рейтинга-напарник-'));

const КОРЕНЬ = path.join(__dirname, '..');
const гдеЛомать = process.argv.indexOf('--сломать');
const ЛОМАТЬ = гдеЛомать !== -1;

let всегоПроверок = 0;
let ошибок = 0;

function равно(что, было, надо) {
  всегоПроверок++;
  const ок = было === надо;
  if (!ок) ошибок++;
  console.log((ок ? '  ✓' : '  ✗') + ' ' + что + ': ' + было + (ок ? '' : ' (ждали ' + надо + ')'));
}

/** Заменить ровно одно вхождение, иначе приём порчи устарел — сказать вслух. */
function заменитьРовноОдин(файл, старое, новое) {
  const части = fs.readFileSync(файл, 'utf8').split(старое);
  if (части.length !== 2) {
    throw new Error('приём порчи устарел: «' + старое + '» встречается в ' + файл + ' ' +
      (части.length - 1) + ' раз(а) вместо одного — поправьте проверку тем же коммитом');
  }
  fs.writeFileSync(файл, части.join(новое), 'utf8');
}

/** Откуда брать код: из проекта или из испорченной копии. */
function кодИзКопииИлиПроекта() {
  if (!ЛОМАТЬ) return КОРЕНЬ;
  const аргумент = process.argv[гдеЛомать + 1];
  // Проверяем, что после --сломать нет лишних аргументов
  if (аргумент && аргумент.indexOf('--') !== 0) {
    console.error('ОШИБКА: после --сломать не допускаются аргументы; копия создаётся во временной папке');
    process.exit(2);
  }
  // Копия ВСЕГДА во временной папке
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'очки-рейтинга-напарник-сломать-'));
  fs.mkdirSync(папка, { recursive: true });
  // Боевые данные в копию не везём — они не нужны и не наши.
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(папка, 'server'), {
    recursive: true,
    filter: function (откуда) {
      const имя = path.basename(откуда);
      return имя !== 'данные' && имя !== 'node_modules';
    }
  });
  fs.mkdirSync(path.join(папка, 'js'), { recursive: true });
  fs.copyFileSync(path.join(КОРЕНЬ, 'js', 'игры-реестр.js'), path.join(папка, 'js', 'игры-реестр.js'));
  // Порча: убираем умножение на 0.5 для напарников.
  заменитьРовноОдин(path.join(папка, 'server', 'рейтинг.js'),
    '(этоНапарник ? 0.5 : 1)',
    '1 /* ИСПОРЧЕНО --сломать: напарник не получает 0.5 */');
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: код из испорченной копии ' + папка + ' — прогон обязан провалиться ***\n');
  return папка;
}

const КОД = кодИзКопииИлиПроекта();
process.env.GAMES_DATA = fs.mkdtempSync(path.join(os.tmpdir(), 'очки-рейтинга-напарник-данные-'));
const рейтинг = require(path.join(КОД, 'server', 'рейтинг.js'));

/** Живой игрок за столом. Исход — 'победа', 'ничья' или 'поражение'. */
function человек(номер, исход, напарник) {
  return {
    номер: номер, имя: 'Т' + номер, этоБот: false,
    победил: исход === 'победа', ничья: исход === 'ничья',
    напарник: напарник === undefined ? null : напарник
  };
}

/** Сколько очков у игрока в этой игре сейчас. */
function очки(номер, игра) {
  const срез = рейтинг.срезДляИгрока(игра || 'дурак', номер);
  return срез.я ? срез.я.очки : 0;
}

