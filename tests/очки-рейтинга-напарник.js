/* =====================================================================
   ОЧКИ РЕЙТИНГА: ЗА НАПАРНИКА В ИГРЕ 2 НА 2 — НОЛЬ.

   Что проверяем. Решение владельца 30.09 09:31: «за напарника 0, по 20
   за победу пары». В учестьПартию (server/рейтинг.js) напарник (поле
   игрок.напарник) пропускается целиком: очков за него нет при любом
   исходе, и через ограничитель сговора («не больше 5 партий с одним
   человеком в сутки») он тоже не идёт. До 30.09 за напарника платили
   половину цены, и победа пары давала по 25.

   Цены берём из сервера (рейтинг.ЦЕНА), а не из головы.

   Сценарии:
     1) пара победила двух живых: каждому 10 + 10 = 20, проигравшим 0;
     2) все четверо вничью: каждому 5 + 5 = 10 (за напарника ничего);
     3) обычная партия вдвоём без напарника — как всегда: 10 и 0;
     4) и 5) разный исход внутри пары — каждому только за соперников;
     6) ЗА НАПАРНИКА РОВНО 0 ПРИ ПОБЕДЕ: пара обыграла двух лёгких ботов
        (они стоят 0) — весь итог и есть доля за напарника, ждём 0;
     7) ЗА НАПАРНИКА РОВНО 0 ПРИ НИЧЬЕЙ: ничья с двумя ботами (ничья
        с ботом стоит 0) — ждём 0;
     8) ПРИ ПОРАЖЕНИИ очков и так нет, поэтому проверяем другое: шесть
        проигранных вместе партий не съедают зачёт пары. Потом эти двое
        садятся друг против друга — победа обязана принести полную цену.

   УМЕЕТ КРАСНЕТЬ:
     node tests/очки-рейтинга-напарник.js --сломать
   копирует server/ (без server/данные) и общее/js/игры-реестр.js во временную
   папку системы, в КОПИИ server/рейтинг.js возвращает старое правило
   (за напарника половина цены, через ограничитель сговора) и гоняет те же
   проверки на копии — прогон обязан провалиться. Файлы проекта не трогаются.

   Боевых данных не касается: папка данных (GAMES_DATA) — временная.

   Запуск: node tests/очки-рейтинга-напарник.js
   Выход 0 — провалов нет.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const гдеЛомать = process.argv.indexOf('--сломать');
const ЛОМАТЬ = гдеЛомать !== -1;

let всегоПроверок = 0;
let ошибок = 0;

function равно(что, было, надо) {
  всегоПроверок++;
  const ок = было === надо;
  if (!ок) ошибок++;
  console.log((ок ? '  ✓' : '  ✗') + ' ' + что + ': ' + было + (ок ? '' : ' (ждали ' + надо + ')'));
}

/** Заменить ровно одно вхождение, иначе приём порчи устарел — сказать вслух. */
function заменитьРовноОдин(файл, старое, новое) {
  const части = fs.readFileSync(файл, 'utf8').split(старое);
  if (части.length !== 2) {
    throw new Error('приём порчи устарел: «' + старое + '» встречается в ' + файл + ' ' +
      (части.length - 1) + ' раз(а) вместо одного — поправьте проверку тем же коммитом');
  }
  fs.writeFileSync(файл, части.join(новое), 'utf8');
}

/* Старое правило (до 30.09) словами кода: напарник проходит ограничитель
   сговора и приносит половину цены. Вставляется в КОПИЮ вместо пропуска. */
const СТАРОЕ_ПРАВИЛО_НАПАРНИКА =
  'if (этоНапарник) {\n' +
  '        /* ИСПОРЧЕНО --сломать: за напарника снова половина цены, как до 30.09 */\n' +
  '        if (параЕщёВЗачёте(запись, другой.номер, сегодня)) {\n' +
  "          const заНапарника = начислить(запись, 'человек', Math.floor(ценаСоперника(другой, исход) * 0.5), сегодня);\n" +
  '          добавлено[игрок.номер] += заНапарника;\n' +
  '          if (половина) половина.очки += заНапарника;\n' +
  '          половинаСостава.очки += заНапарника;\n' +
  '        }\n' +
  '        continue;\n' +
  '      }';

/** Откуда брать код: из проекта или из испорченной копии во временной папке. */
function кодИзКопииИлиПроекта() {
  if (!ЛОМАТЬ) return КОРЕНЬ;
  const аргумент = process.argv[гдеЛомать + 1];
  if (аргумент && аргумент.indexOf('--') !== 0) {
    console.error('ОШИБКА: после --сломать не допускаются аргументы; копия создаётся во временной папке');
    process.exit(2);
  }
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'очки-рейтинга-напарник-сломать-'));
  // Боевые данные в копию не везём — они не нужны и не наши.
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(папка, 'server'), {
    recursive: true,
    filter: function (откуда) {
      const имя = path.basename(откуда);
      return имя !== 'данные' && имя !== 'node_modules';
    }
  });
  require('./пути-проекта.js').создатьПапкиКода(папка);
  fs.copyFileSync(path.join(КОРЕНЬ, 'общее', 'js', 'игры-реестр.js'), path.join(папка, 'общее', 'js', 'игры-реестр.js'));
  заменитьРовноОдин(path.join(папка, 'server', 'рейтинг.js'), 'if (этоНапарник) continue;', СТАРОЕ_ПРАВИЛО_НАПАРНИКА);
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: код из испорченной копии ' + папка + ' — прогон обязан провалиться ***\n');
  return папка;
}

const КОД = кодИзКопииИлиПроекта();
process.env.GAMES_DATA = fs.mkdtempSync(path.join(os.tmpdir(), 'очки-рейтинга-напарник-данные-'));
const рейтинг = require(path.join(КОД, 'server', 'рейтинг.js'));
const ЗА_ЧЕЛОВЕКА = рейтинг.ЦЕНА.человек;

/** Живой игрок за столом. Исход — 'победа', 'ничья' или 'поражение'. */
function человек(номер, исход, напарник) {
  return {
    номер: номер, имя: 'Т' + номер, этоБот: false,
    победил: исход === 'победа', ничья: исход === 'ничья',
    напарник: напарник === undefined ? null : напарник
  };
}
function бот(уровень, исход) {
  return { этоБот: true, уровень: уровень, победил: исход === 'победа', ничья: исход === 'ничья' };
}

/** Сколько очков у игрока в этой игре сейчас. */
function очки(номер, игра) {
  const срез = рейтинг.срезДляИгрока(игра || 'дурак', номер);
  return срез.я ? срез.я.очки : 0;
}

console.log('=== Очки рейтинга: за напарника в игре 2 на 2 — ноль ===');
