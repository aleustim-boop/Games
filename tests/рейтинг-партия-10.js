'use strict';

/* Проверка партии 10-А рейтинга (js/рейтинг-экран.js) — два остатка чек-листа
   приёмки макета (штаб/план-рейтинг-партия-10.md, сверка docs/05_ACCEPTANCE_RU.md
   и qa/VALIDATION_RU.md):

   1. Длинное имя нигде не раскрывается — css обрезает его многоточием, но узнать
      имя целиком было нечем (ни title, ни aria-label). Теперь общая помощница
      «ячейкаИмени» ставит title = полное имя ВСЕГДА (не только когда обрезано —
      проще и честнее решение штаба), и этим разом закрывает все три места, где
      она стоит: строку таблицы, подиум и карточку «Моё место».
   2. Активный пункт шторки выбора игры не был помечен для читалки экрана —
      только классом и текстовой галочкой «✓». Список — обычные кнопки без
      role="listbox"/"option" (в «контейнер» role не задаётся), поэтому пометка —
      aria-current="true" (не aria-selected: тот требует role option/tab/row,
      которого здесь нет).

   Песочница vm по образцу tests/рейтинг-страница-2-экран.js — без браузера,
   поддельный fetch отвечает по игре из тела запроса.

   Сценарии:
   1. Длинное имя (40+ знаков) на подиуме (топ-1), в обычной строке таблицы
      (место 5) и в карточке «Моё место» — title у всех трёх узлов совпадает
      с полным именем без обрезки.
   2. Открыта шторка выбора игры на «дурак» — ровно один пункт с
      aria-current="true", и это тот же пункт, что несёт класс «--активна»
      (id «рейтинг-панель-игр-пункт-дурак»).
   3. Смена игры на «шашки» через пункт шторки и повторное открытие шторки —
      отметка aria-current переезжает на пункт «шашки», у пункта «дурак» её
      больше нет.

   Ломающий запуск --сломать: портит КОПИЮ js/рейтинг-экран.js в отдельном
   файле во временной папке (os.tmpdir(), файл проекта не трогаем) — убирает
   и присвоение title в «ячейкаИмени», и setAttribute('aria-current', …) в
   «пунктПанелиИгр». Ожидаемо краснеют все проверки title (сценарий 1) и все
   проверки aria-current (сценарии 2 и 3). */

const fs = require('fs');
const os = require('os');
const path = require('path');
const бр = require(path.join(__dirname, 'поддельный-браузер.js'));

const КОРЕНЬ = path.join(__dirname, '..');
const FILE_ARG = process.argv.find(function (д) { return д.indexOf('--файл=') === 0; });
const файлРейтинга = FILE_ARG ? FILE_ARG.split('=')[1] : path.join(КОРЕНЬ, 'js', 'рейтинг-экран.js');
const исходник = fs.readFileSync(файлРейтинга, 'utf8');

const СЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;
let исходникРабочий = исходник;

if (СЛОМАТЬ) {
  const ИСКОМОЕ_TITLE = 'элемент.title = имя;';
  const ИСКОМОЕ_ARIA = "if (активна) кнопка.setAttribute('aria-current', 'true');";
  if (исходник.indexOf(ИСКОМОЕ_TITLE) === -1 || исходник.indexOf(ИСКОМОЕ_ARIA) === -1) {
    console.log('ОШИБКА: приём порчи --сломать устарел (устройство изменилось) — ' +
      'не нашлись искомые строки в ' + файлРейтинга);
    process.exit(1);
  }
  let испорченный = исходник.split(ИСКОМОЕ_TITLE).join(
    '/* порчено --сломать: title никогда не ставится */'
  );
  испорченный = испорченный.split(ИСКОМОЕ_ARIA).join(
    '/* порчено --сломать: aria-current никогда не ставится */'
  );
  const файлКопии = path.join(os.tmpdir(), 'рейтинг-экран-испорчен-10-' + Date.now() + '.js');
  fs.writeFileSync(файлКопии, испорченный, 'utf8');
  исходникРабочий = fs.readFileSync(файлКопии, 'utf8');
  console.log('Ломающий запуск --сломать: порчу КОПИЮ в ' + файлКопии + ' (файл проекта не трогаю) —');
  console.log('  убираю title в «ячейкаИмени» и aria-current в «пунктПанелиИгр».');
  console.log('  Ожидаю провал: все проверки title (сценарий 1) и все проверки aria-current (сценарии 2, 3).');
  console.log('');
}

let провалов = 0;
let всегоПроверок = 0;

function проверить(имя, годно) {
  всегоПроверок += 1;
  console.log((годно ? '  ok  ' : ' ПЛОХО ') + имя);
  if (!годно) провалов += 1;
}

function ждать(мс) { return new Promise(function (r) { setTimeout(r, мс || 40); }); }

function игрок(место, имя, очки, этоЯ) {
  return { место: место, имя: имя, очки: очки, побед: место, партий: место + 5, этоЯ: !!этоЯ };
}

function сделатьFetch(обработать) {
  const функция = function (адрес, настройки) {
    const тело = JSON.parse((настройки && настройки.body) || '{}');
    return Promise.resolve(обработать(тело)).then(function (данные) {
      return { json: function () { return Promise.resolve(данные); } };
    });
  };
  return функция;
}

/* Три длинных имени (40+ знаков — проверяется ниже самим тестом, не на глаз):
   топ-1 подиума, пятое место обычной строки таблицы и «я» карточки «Моё
   место». Разные имена, чтобы точно знать, какой узел за какое отвечает. */
const ДЛИННОЕ_ИМЯ_ПОДИУМ = 'Александра Константиновна Синеокая-Долгорукая';
const ДЛИННОЕ_ИМЯ_СТРОКА = 'Пелагея Никифоровна Длинноволосая-Многобуквенная';
const ДЛИННОЕ_ИМЯ_КАРТОЧКА = 'Владимир Аполлинариевич Семираменский-Длиннофамильный';

проверить('сами тестовые имена действительно длинные (40+ знаков) — тест не врёт себе',
  ДЛИННОЕ_ИМЯ_ПОДИУМ.length >= 40 && ДЛИННОЕ_ИМЯ_СТРОКА.length >= 40 && ДЛИННОЕ_ИМЯ_КАРТОЧКА.length >= 40);

/* Верхушка: место 1 — длинное имя подиума (топ-3 уходит на подиум), место 5 —
   длинное имя обычной строки (остаётся в таблице, за подиумом). */
const верхушкаБаза = [];
for (let м = 1; м <= 10; м++) {
  const имя = м === 1 ? ДЛИННОЕ_ИМЯ_ПОДИУМ : (м === 5 ? ДЛИННОЕ_ИМЯ_СТРОКА : 'Игрок Номер' + м);
  верхушкаБаза.push(игрок(м, имя, 30000 - м * 100));
}
/* Окно вокруг своего места — «я» на месте 50, длинное имя карточки. */
const вокругБаза = [];
for (let м = 48; м <= 52; м++) {
  вокругБаза.push(игрок(м, м === 50 ? ДЛИННОЕ_ИМЯ_КАРТОЧКА : 'Сосед' + м, 20000 - м, м === 50));
}

function ответДурак() {
  return {
    узналиВас: true, всего: 200, яВТаблице: true,
    я: игрок(50, ДЛИННОЕ_ИМЯ_КАРТОЧКА, 19940, true),
    верхушка: верхушкаБаза.slice(), вокругМеня: вокругБаза.slice(),
    продолжение: null
  };
}

const ответШашки = {
  узналиВас: true, всего: 5, яВТаблице: true,
  я: игрок(2, 'Я В Шашках', 500, true),
  верхушка: [игрок(1, 'Первый Шашист', 600), игрок(2, 'Я В Шашках', 500, true),
    игрок(3, 'Третий Шашист', 400)],
  вокругМеня: [игрок(2, 'Я В Шашках', 500, true)]
};

async function прогон() {
  const fetch = сделатьFetch(function (тело) {
    return тело.игра === 'шашки' ? ответШашки : ответДурак();
  });

  const п = бр.поднять(исходникРабочий, { имяФайла: 'js/рейтинг-экран.js', fetch: fetch });
  п.окно.ЭкранРейтинга.открыть('дурак');
  await ждать();

  /* ---- Сценарий 1: title = полное имя на подиуме, в строке и в карточке ---- */
  const узлыПодиума = п.документ.querySelectorAll('.рейтинг-подиум-имя');
  const подиумИмени = узлыПодиума.filter(function (у) { return у.textContent.indexOf(ДЛИННОЕ_ИМЯ_ПОДИУМ) === 0; })[0];
  проверить('длинное имя нашлось на подиуме (топ-1)', Boolean(подиумИмени));
  проверить('title подиума совпадает с полным именем целиком',
    Boolean(подиумИмени) && подиумИмени.title === ДЛИННОЕ_ИМЯ_ПОДИУМ);

  const узлыСтрок = п.документ.querySelectorAll('.рейтинг-имя');
  const строкаИмени = узлыСтрок.filter(function (у) { return у.textContent.indexOf(ДЛИННОЕ_ИМЯ_СТРОКА) === 0; })[0];
  проверить('длинное имя нашлось в обычной строке таблицы (место 5)', Boolean(строкаИмени));
  проверить('title строки таблицы совпадает с полным именем целиком',
    Boolean(строкаИмени) && строкаИмени.title === ДЛИННОЕ_ИМЯ_СТРОКА);

  const карточкаИмени = п.документ.querySelector('.рейтинг__карточка-имя');
  проверить('карточка «Моё место» с длинным именем нашлась',
    Boolean(карточкаИмени) && карточкаИмени.textContent.indexOf(ДЛИННОЕ_ИМЯ_КАРТОЧКА) === 0);
  проверить('title карточки «Моё место» совпадает с полным именем целиком',
    Boolean(карточкаИмени) && карточкаИмени.title === ДЛИННОЕ_ИМЯ_КАРТОЧКА);

  /* ---- Сценарий 2: ровно один пункт шторки с aria-current, тот же — активный ---- */
  п.документ.getElementById('рейтинг-выбор-игры-кнопка').click();
  const пункты1 = п.документ.querySelectorAll('.рейтинг-панель-игр__пункт');
  проверить('в шторке нашлись пункты игр', пункты1.length > 0);
  const сТекущимОтметка1 = пункты1.filter(function (у) { return у.getAttribute('aria-current') === 'true'; });
  проверить('ровно один пункт шторки с aria-current="true" (игра «дурак»)', сТекущимОтметка1.length === 1);
  проверить('это пункт «дурак»',
    сТекущимОтметка1.length === 1 && сТекущимОтметка1[0].id === 'рейтинг-панель-игр-пункт-дурак');
  проверить('у него же класс «--активна»',
    сТекущимОтметка1.length === 1 && сТекущимОтметка1[0].classList.contains('рейтинг-панель-игр__пункт--активна'));
  const дурак1 = п.документ.getElementById('рейтинг-панель-игр-пункт-шашки');
  проверить('у невыбранного пункта «шашки» aria-current нет вовсе',
    Boolean(дурак1) && дурак1.getAttribute('aria-current') !== 'true');

  /* ---- Сценарий 3: смена игры — отметка переезжает на другой пункт ---- */
  п.документ.getElementById('рейтинг-панель-игр-пункт-шашки').click();
  await ждать();

  п.документ.getElementById('рейтинг-выбор-игры-кнопка').click();
  const пункты2 = п.документ.querySelectorAll('.рейтинг-панель-игр__пункт');
  const сТекущимОтметка2 = пункты2.filter(function (у) { return у.getAttribute('aria-current') === 'true'; });
  проверить('после смены игры снова ровно один пункт с aria-current="true"', сТекущимОтметка2.length === 1);
  проверить('теперь это пункт «шашки»',
    сТекущимОтметка2.length === 1 && сТекущимОтметка2[0].id === 'рейтинг-панель-игр-пункт-шашки');
  проверить('и у него же класс «--активна»',
    сТекущимОтметка2.length === 1 && сТекущимОтметка2[0].classList.contains('рейтинг-панель-игр__пункт--активна'));
  const дурак2 = п.документ.getElementById('рейтинг-панель-игр-пункт-дурак');
  проверить('у пункта «дурак» отметки aria-current больше нет',
    Boolean(дурак2) && дурак2.getAttribute('aria-current') !== 'true');

  проверить('ошибок в консоли нет', п.ошибкиКонсоли.length === 0);

  console.log('');
  console.log('Итого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
  if (провалов) process.exit(1);
}

прогон().catch(function (ошибка) {
  console.error('Ошибка прогона:', ошибка);
  process.exit(1);
});
