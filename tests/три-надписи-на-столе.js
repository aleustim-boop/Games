/* =====================================================================
   ТРИ НАДПИСИ НА СТОЛЕ НЕ ПОВТОРЯЮТ ДРУГ ДРУГА.

   Правило штаба для нового стола (11 сентября, макет владельца): место
   соперника, пилюля «Вы» (#статус-хода) и строка подсказки говорят РАЗНОЕ.
   Кто ходит и кто отбивается — видно на месте игрока; своё состояние
   человек видит в пилюле; что нажать — в подсказке.

   Для каждого снимка партии:
     1) подсказка и пилюля не совпадают и не содержат одна другую;
     2) в пилюле нет имён соперников («Бот 3 отбивается» — нельзя);
     3) в подсказке нет надписи с места соперника («отбивается», «ходит»…);
     4) в пилюле тоже нет надписи с места соперника;
     5) после сказанного «Пас» пилюля — «Ваше слово»;
     6) подсказка не называет напарника.
   Подсказка — устойчивая часть строки (текстДействия), без мимолётных
   новостей слева: правило про то, что висит на экране, пока человек думает.

   Снимки раскладываются по положениям партии: ваш ход, отбиваетесь,
   подкидываете, ход соперника, соперник отбивается, вы вышли, конец.

   Написал разработчик, тестировщик перенёс в tests/ и добавил проверку
   проверки: node tests/три-надписи-на-столе.js 8080 сломать — подсказка
   нарочно повторяет пилюлю, и проверка обязана покраснеть.

   Запуск (страничный сервер уже поднят):
       node tests/три-надписи-на-столе.js            (страницы на 8080)
       node tests/три-надписи-на-столе.js 8141
   ===================================================================== */
const path = require('path');
const { chromium, подготовитьПодделку } = require(path.join(__dirname, 'браузер-робот.js'));
const АДРЕС = 'http://127.0.0.1:' + (process.argv[2] && /^\d+$/.test(process.argv[2]) ? process.argv[2] : '8080') + '/';
const СЛОМАТЬ = process.argv.indexOf('сломать') !== -1;

function снимокТрёхНадписей() {
  const ф = фаза(партия);
  const мойХод = сейчасМойХод();
  const отбиваюсь = этоЯОтбиваюсь();
  const места = [...document.querySelectorAll('#соперники .соперник')].map((у) => ({
    имя: ((у.querySelector('.соперник__имя') || {}).textContent || '').trim(),
    метка: ((у.querySelector('.соперник__метка') || {}).textContent || '').trim()
  }));
  // Вдвоём место соперника — строка с его именем.
  const имяВдвоём = ((document.querySelector('#счётчик-бота .счётчик__имя') || {}).textContent || '').replace(/:$/, '').trim();
  const я = (местаКомпании() || []).find((м) => м.этоЯ) || null;
  let положение;
  if (партия.завершена || ф === 'конец') положение = 'конец';
  else if (я && (я.выбыл || я.ушёл)) положение = 'вы вышли';
  else if (мойХод && отбиваюсь && ф === 'защита') положение = 'отбиваетесь';
  else if (мойХод && (ф === 'подкидывание' || ф === 'докидывание')) положение = 'подкидываете';
  else if (мойХод) положение = 'ваш ход';
  else if (ф === 'защита' && !отбиваюсь) положение = 'соперник отбивается';
  else положение = 'ход соперника';
  return {
    положение,
    пилюля: ((document.getElementById('статус-хода') || {}).textContent || '').trim(),
    подсказка: картыДляЧеловека(текстДействия() || '').trim(),
    места,
    имена: места.map((м) => м.имя).concat(этоКомпания() ? [] : [имяВдвоём]).filter(Boolean)
  };
}

function нарушения(с) {
  const чисто = (т) => т.toLowerCase().replace(/…/g, '').replace(/\s+/g, ' ').trim();
  const п = чисто(с.пилюля);
  const д = чисто(с.подсказка);
  const найдено = [];
  if (п && д && (п === д || п.indexOf(д) !== -1 || д.indexOf(п) !== -1)) найдено.push('подсказка повторяет пилюлю');
  for (const имя of с.имена) {
    if (п && п.indexOf(чисто(имя)) !== -1) найдено.push('в пилюле имя «' + имя + '»');
  }
  for (const м of с.места) {
    if (!м.метка) continue;
    const метка = чисто(м.метка);
    if (д && д.indexOf(метка) !== -1) найдено.push('подсказка повторяет место «' + м.имя + ': ' + м.метка + '»');
    if (п && п.indexOf(метка) !== -1) найдено.push('пилюля повторяет место «' + м.имя + ': ' + м.метка + '»');
  }
  // Замечание ревьюера а): слово вернулось после «Пас» — подкинуть уже нельзя.
  if (/пасовали|пасуем/.test(д) && с.пилюля !== 'Ваше слово') {
    найдено.push('подсказка про сказанный «Пас», а пилюля «' + с.пилюля + '» (надо «Ваше слово»)');
  }
  // Замечание ревьюера б): напарника называет только его место.
  if (д.indexOf('напарник') !== -1) найдено.push('подсказка называет напарника');
  return найдено;
}

async function ход(страница) {
  return страница.evaluate(() => {
    const к = (id) => document.getElementById(id);
    const можно = [...document.querySelectorAll('#карты-человека .карта--можно')];
    const выбрана = document.querySelector('#карты-человека .карта--выбрана');
    const цель = document.querySelector('#стол .пара--цель');
    if (выбрана && цель) { цель.click(); return 'бью'; }
    // Кнопки стола видны всегда; нажать можно только невыключенную.
    if (!к('кнопка-беру').disabled) {
      if (можно.length) { можно[0].click(); return 'поднял'; }
      к('кнопка-беру').click(); return 'взял';
    }
    const бито = к('кнопка-завершить');
    if (!бито.disabled && !бито.classList.contains('скрыт')) {
      if (можно.length && Math.random() < 0.7) { можно[0].click(); return 'подкинул'; }
      бито.click(); return 'бито';
    }
    if (можно.length) { можно[0].click(); return 'сходил'; }
    return '';
  });
}

(async () => {
  if (СЛОМАТЬ) console.log('РЕЖИМ «СЛОМАТЬ»: подсказка нарочно повторяет пилюлю — проверка обязана покраснеть.\n');
  const браузер = await chromium.launch();
  const итог = {};
  const редкие = { послеПаса: [], мимо: [] };
  let всегоНарушений = 0;
  let всегоСнимков = 0;
  const примеры = [];
  /* Компанией и парами — по две партии: «слово после Пас» бывает редко. */
  /* В режиме «сломать» довольно одной партии вдвоём: повтор там на каждом
     шагу, и ждать десять партий, чтобы увидеть красное, незачем. */
  const столы = СЛОМАТЬ ? [{ игроков: 2 }]
    : [{ игроков: 2 }, { игроков: 3 }, { игроков: 3 }, { игроков: 4 }, { игроков: 4, парами: true }];
  for (const стол of столы) {
    const игроков = стол.игроков;
    for (let партияНомер = 0; партияНомер < (СЛОМАТЬ ? 1 : 2); партияНомер++) {
      const окно = await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
      const страница = await окно.newPage();
      await подготовитьПодделку(страница, { версия: '8.0', полныйЭкран: 'дают' });
      await страница.goto(АДРЕС);
      await страница.waitForFunction(() => typeof настройкиИгрыСБотами !== 'undefined');
      await страница.waitForTimeout(400);
      await страница.click('#кнопка-игра-дурак');
      await страница.waitForTimeout(250);
      await страница.evaluate((с) => {
        настройкиИгрыСБотами.игроков = с.игроков;
        настройкиИгрыСБотами.парами = с.парами === true;
      }, стол);
      if (СЛОМАТЬ) {
        await страница.evaluate(() => { window.текстДействия = function () { return статусХода(); }; });
      }
      await страница.click('#кнопка-режим-бот');
      await страница.waitForTimeout(1300);
      for (let шаг = 0; шаг < 260; шаг++) {
        const с = await страница.evaluate(снимокТрёхНадписей);
        всегоСнимков++;
        const н = нарушения(с);
        if (/пасовали|пасуем/.test(с.подсказка)) редкие.послеПаса.push(с.пилюля);
        if (/Подход мимо вас/.test(с.подсказка)) редкие.мимо.push(с.пилюля);
        const ключ = (стол.парами ? 'парами' : (игроков === 2 ? 'вдвоём' : 'компания')) + ' · ' + с.положение;
        итог[ключ] = итог[ключ] || { снимков: 0, нарушений: 0 };
        итог[ключ].снимков++;
        if (н.length) {
          итог[ключ].нарушений++;
          всегоНарушений++;
          if (примеры.length < 14 && !примеры.some((п) => п.indexOf('«' + с.пилюля + '» | «' + с.подсказка + '»') !== -1)) {
            примеры.push(ключ + ': «' + с.пилюля + '» | «' + с.подсказка + '» | места: ' +
              с.места.map((м) => м.имя + '=' + м.метка).join(', ') + ' → ' + н.join('; '));
          }
        }
        const конец = await страница.evaluate(() => document.getElementById('экран-результата').classList.contains('экран--виден'));
        if (конец) break;
        const что = await ход(страница);
        await страница.waitForTimeout(что ? 380 : 650);
      }
      await окно.close();
    }
  }
  await браузер.close();
  console.log('Снимки по положениям (снимков / с нарушением):');
  for (const ключ of Object.keys(итог).sort()) console.log('  ' + ключ + ': ' + итог[ключ].снимков + ' / ' + итог[ключ].нарушений);
  const разные = (список) => [...new Set(список)].join(', ') || '—';
  console.log('Слово после «Пас» (подсказка «пасовали/пасуем»): снимков ' + редкие.послеПаса.length +
    ', пилюля: ' + разные(редкие.послеПаса));
  console.log('«Подход мимо вас»: снимков ' + редкие.мимо.length + ', пилюля: ' + разные(редкие.мимо));
  if (примеры.length) console.log('Примеры нарушений:\n  ' + примеры.join('\n  '));
  /* Проверка, которая ничего не видела, ничего и не доказала. */
  if (всегоСнимков < (СЛОМАТЬ ? 20 : 100)) {
    console.log('ИТОГ: КРАСНО — снимков всего ' + всегоСнимков + ', смотреть было не на что');
    process.exit(1);
  }
  console.log(всегоНарушений ? 'ИТОГ: КРАСНО — нарушений ' + всегоНарушений : 'ИТОГ: зелено — повторов нет (снимков ' + всегоСнимков + ')');
  process.exit(всегоНарушений ? 1 : 0);
})().catch((о) => { console.error('проверка упала: ' + (о && о.stack || о)); process.exit(2); });
