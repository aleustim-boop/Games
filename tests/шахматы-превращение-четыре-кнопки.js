'use strict';

/* =====================================================================
   ПЛАШКА ПРЕВРАЩЕНИЯ ПЕШКИ: ВСЕ ЧЕТЫРЕ КНОПКИ ПАЛЬЦЕМ.

   Плашку не видел никто, а кнопок на ней четыре, и ошибка легко живёт
   в одной из них. Доводить пешку настоящей игрой мы уже пробовали: обе
   стороны упираются пешками лбами, до края никто не доходит, а путь
   пешки правилами и так проверен числами. Поэтому проверяем то, чего
   не проверял никто: САМУ ПЛАШКУ и нажатие.

   Как ставится позиция — без подделки экрана. Перед скриптами страницы
   мы подменяем ровно одну дверь правил: «создатьПартию» отдаёт не
   начальную расстановку, а позицию из FEN, где белая пешка стоит в шаге
   от края. Дальше всё идёт как обычно: правила считают ходы сами, экран
   рисует сам, плашку показывает сам.

   Позиция: 4k3/P7/8/8/8/8/8/4K3 — короли на месте, белая пешка на a7.
   Один ход a7-a8 — и плашка.

   Проверяем в четырёх заходах, по кнопке на заход: ферзь, ладья, слон,
   конь. И смотрим глазами: влезает ли плашка на 320, не мельче ли кнопки
   сорока точек, видно ли, что фигура выбрана.

   Запуск (страничный сервер уже поднят):
       node tests/шахматы-превращение-четыре-кнопки.js 8080
   ===================================================================== */

const { chromium, подготовитьПодделку } = require('./браузер-робот.js');

const ПОРТ = Number(process.argv[2]) || 8080;
const АДРЕС = 'http://127.0.0.1:' + ПОРТ + '/шахматы.html';
const ПАПКА = 'tests/скриншоты/';
const ПОЗИЦИЯ = '4k3/P7/8/8/8/8/8/4K3 w - - 0 1';

let провалов = 0;
function проверить(условие, слова) {
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}
const спать = (мс) => new Promise((ф) => setTimeout(ф, мс));

/* Что должно оказаться на доске после выбора. Знак берём тот же, каким
   игра рисует фигуры (залитые знаки для обеих сторон). */
const ВЫБОРЫ = [
  { имя: 'ферзь', слово: /ферз/i, знак: '♛' },
  { имя: 'ладья', слово: /ладь/i, знак: '♜' },
  { имя: 'слон',  слово: /слон/i, знак: '♝' },
  { имя: 'конь',  слово: /кон/i,  знак: '♞' }
];

async function сЗаданнойПозицией(браузер, ш, в) {
  const окно = await браузер.newContext({ viewport: { width: ш, height: в }, hasTouch: true, deviceScaleFactor: 2 });
  const страница = await окно.newPage();
  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
    красные.push('консоль: ' + м.text());
  });
  await подготовитьПодделку(страница, { версия: '8.0', полныйЭкран: 'дают' });

  /* Подменяем одну дверь правил, как только правила появятся в окне.
     Всё остальное — настоящее: ходы считают правила, рисует экран. */
  await страница.addInitScript((фен) => {
    let настоящие = null;
    Object.defineProperty(window, 'ШахматыПравила', {
      configurable: true,
      get() { return настоящие; },
      set(значение) {
        настоящие = значение;
        if (значение && typeof значение.партияИзFEN === 'function') {
          const былоСоздать = значение.создатьПартию;
          значение.создатьПартию = function () {
            try { return значение.партияИзFEN(фен); } catch (сбой) { return былоСоздать.apply(this, arguments); }
          };
        }
      }
    });
  }, ПОЗИЦИЯ);

  await страница.goto(АДРЕС);
  await спать(700);
  return { окно, страница, красные };
}

(async () => {
  console.log('Плашка превращения: четыре кнопки. Страница: ' + АДРЕС);
  console.log('Позиция: ' + ПОЗИЦИЯ);
  const браузер = await chromium.launch();
  let снимковСделано = 0;

  for (const выбор of ВЫБОРЫ) {
    console.log('\n=== Выбираем: ' + выбор.имя + ' (экран 320×568) ===');
    const { окно, страница, красные } = await сЗаданнойПозицией(браузер, 320, 568);
    await страница.click('#кнопка-вдвоём');
    await спать(700);

    const наДоске = await страница.evaluate(() => document.querySelectorAll('.фигура').length);
    проверить(наДоске === 3, 'позиция поставлена: на доске три фигуры (две короля и пешка), вышло ' + наДоске);

    /* Ходим пешкой на край — обычным пальцем. */
    await страница.evaluate(() => {
      const пешка = [...document.querySelectorAll('.фигура--белая')]
        .sort((а, б) => а.getBoundingClientRect().top - б.getBoundingClientRect().top)
        .find((ф) => /♟/.test(ф.textContent || ''));
      if (пешка) пешка.click();
    });
    await спать(300);
    await страница.evaluate(() => {
      const можно = [...document.querySelectorAll('.поле--можно')]
        .sort((а, б) => а.getBoundingClientRect().top - б.getBoundingClientRect().top);
      if (можно.length) можно[0].click();
    });
    await спать(700);

    const плашка = await страница.evaluate(() => {
      const п = document.getElementById('экран-превращения');
      if (!п || !п.classList.contains('экран--виден')) return { открыта: false };
      const кнопки = [...п.querySelectorAll('button')].filter((к) => к.offsetParent !== null).map((к) => {
        const м = к.getBoundingClientRect();
        return { что: (к.textContent || '').trim().slice(0, 16), ш: Math.round(м.width), в: Math.round(м.height) };
      });
      const м = п.getBoundingClientRect();
      return {
        открыта: true, кнопок: кнопки.length, кнопки: кнопки,
        вОкне: м.top >= -1 && м.bottom <= window.innerHeight + 1,
        мелких: кнопки.filter((к) => к.в < 40).length,
        текст: (п.textContent || '').replace(/\s+/g, ' ').trim().slice(0, 70)
      };
    });

    проверить(плашка.открыта, 'плашка превращения показалась');
    if (!плашка.открыта) { await окно.close(); continue; }

    if (снимковСделано === 0) {
      console.log('  на плашке: «' + плашка.текст + '»');
      console.log('  кнопки: ' + плашка.кнопки.map((к) => к.что + ' ' + к.ш + '×' + к.в).join(', '));
      проверить(плашка.кнопок >= 4, 'кнопок выбора четыре и больше: ' + плашка.кнопок);
      проверить(плашка.вОкне, 'плашка целиком влезает на 320×568');
      проверить(плашка.мелких === 0, 'ни одна кнопка не мельче 40 точек: мелких ' + плашка.мелких);
      await страница.screenshot({ path: ПАПКА + 'шахматы-превращение-320.png' });
      console.log('  снимок: ' + ПАПКА + 'шахматы-превращение-320.png');
      снимковСделано++;
    }

    /* Нажимаем нужную кнопку пальцем — по надписи, а не по порядку:
       порядок кнопок может поменяться, а слово видит человек. */
    const нажали = await страница.evaluate((слово) => {
      const п = document.getElementById('экран-превращения');
      const кнопки = [...п.querySelectorAll('button')].filter((к) => к.offsetParent !== null);
      const нужная = кнопки.find((к) => new RegExp(слово, 'i').test(к.textContent || ''));
      if (!нужная) return { нашли: false, были: кнопки.map((к) => (к.textContent || '').trim()) };
      нужная.click();
      return { нашли: true, надпись: (нужная.textContent || '').trim() };
    }, выбор.слово.source);
    проверить(нажали.нашли, 'кнопка «' + выбор.имя + '» на плашке есть' +
      (нажали.нашли ? ' («' + нажали.надпись + '»)' : ' — были: ' + (нажали.были || []).join(', ')));
    if (!нажали.нашли) { await окно.close(); continue; }

    await спать(900);
    const итог = await страница.evaluate((знак) => {
      const п = document.getElementById('экран-превращения');
      const фигуры = [...document.querySelectorAll('.фигура')];
      /* Искать «самую верхнюю белую» нельзя: после хода доска
         переворачивается к сопернику, и сверху оказывается белый король.
         Поэтому просто смотрим, есть ли среди БЕЛЫХ фигура с нужным знаком. */
      const белые = фигуры.filter((ф) => ф.classList.contains('фигура--белая'));
      const нужная = белые.find((ф) => (ф.textContent || '').indexOf(знак) !== -1);
      const верхняя = нужная || белые[0];
      return {
        плашкаОткрыта: п.classList.contains('экран--виден'),
        фигур: фигуры.length,
        верхняяЗнак: верхняя ? (верхняя.textContent || '').trim() : '',
        совпало: !!нужная,
        белыеЗнаки: белые.map((ф) => (ф.textContent || '').trim()).join(' '),
        строка: (document.getElementById('строка-хода') || {}).textContent || ''
      };
    }, выбор.знак);

    console.log('  после выбора: плашка открыта ' + итог.плашкаОткрыта + ', фигур ' + итог.фигур +
      ', белые фигуры: ' + итог.белыеЗнаки + ', строка «' + итог.строка.trim().slice(0, 40) + '»');
    проверить(!итог.плашкаОткрыта, выбор.имя + ': выбор пальцем закрывает плашку');
    проверить(итог.фигур === 3, выбор.имя + ': фигур по-прежнему три — пешка сменилась, а не пропала');
    проверить(итог.совпало, выбор.имя + ': на краю встала именно выбранная фигура (ждали «' + выбор.знак + '»)');
    проверить(красные.length === 0, выбор.имя + ': консоль чистая' +
      (красные.length ? ': ' + красные.join(' | ') : ''));

    if (выбор.имя === 'конь') {
      await страница.screenshot({ path: ПАПКА + 'шахматы-превращение-выбран-конь.png' });
      console.log('  снимок: ' + ПАПКА + 'шахматы-превращение-выбран-конь.png');
    }
    await окно.close();
  }

  await браузер.close();
  console.log('\nИтог: провалов ' + провалов);
  process.exit(провалов ? 1 : 0);
})().catch((о) => { console.error('Стенд упал: ' + (о && о.stack || о)); process.exit(2); });
