#!/usr/bin/env node
'use strict';

/* =====================================================================
   НИЧЬЯ «РАЗОМ» В РЕЙТИНГЕ — карты кончились у всех сидящих одновременно.

   Что проверяет (находка ревьюера). Правила (js/game.js, «записатьИтог»)
   пишут строковый партия.результат = 'ничья', когда проигравших нет
   (проверитьКонец → записатьИтог([])), но раньше НЕ ставили булево поле
   партия.ничья. Сервер же (server/комнаты.js: ничьяВПартии, строка
   ~2720) считает партию ничьей только по partия.ничья === true, а
   «победил» у застольеДляРейтинга — это «не в списке проигравших». Итог
   без починки: пустой список проигравших → каждый сидящий получает
   в рейтинге победу вместо честной ничьей.

   Проверка идёт настоящими правилами, а не пересказом: партия готовится
   так, чтобы у всех сидящих руки опустели одновременно при пустой
   колоде, и через игра.завершитьПодход(партия) вызывается тот же путь,
   что и в живой игре (завершитьПодход → проверитьКонец → записатьИтог).
   Дальше готовая партия отдаётся в server/комнаты.js:застольеДляРейтинга
   — так же, как это делает комната по-настоящему (см. tests/сеть-итог-по-кругу.js).

   Три случая:
     1) вдвоём, карты кончились у обоих разом — ничья;
     2) парами (4 места), у обеих пар карт не осталось — ничья;
     3) отрицательный: у одного из двоих ещё есть карта — обычный дурак,
        партия.ничья остаётся false (проверка, что починка не зацепила
        нормальный конец партии).

   ЛОМАЮЩИЙ ЗАПУСК (вручную, копия не в проекте):
     1) скопировать js/game.js во временную папку (%TEMP%/os.tmpdir());
     2) в копии убрать строку «партия.ничья = true;» внутри записатьИтог;
     3) node tests/дурак-ничья-разом-в-рейтинг.js --game=<путь к копии>
     4) проверка обязана покраснеть — ничья без поля partия.ничья
        превращается в рейтинге в победу всех, и первая же проверка
        падает.

   Запуск:
     node tests/дурак-ничья-разом-в-рейтинг.js                обычный прогон
     node tests/дурак-ничья-разом-в-рейтинг.js --game=<путь>  правила из копии
   ===================================================================== */

const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ДОВОД_ИГРЫ = process.argv.find(function (a) { return a.indexOf('--game=') === 0; });
const ПУТЬ_ИГРЫ = ДОВОД_ИГРЫ ? ДОВОД_ИГРЫ.slice('--game='.length) : path.join(КОРЕНЬ, 'js', 'game.js');

const игра = require(ПУТЬ_ИГРЫ);
// Рейтинговый путь — всегда настоящий: ломающий запуск портит только правила игры.
const комнаты = require(path.join(КОРЕНЬ, 'server', 'комнаты.js'));

console.log('Правила из: ' + ПУТЬ_ИГРЫ);

let проверок = 0;
let провалов = 0;
function проверить(условие, что) {
  проверок++;
  if (условие) {
    console.log('  ✓ ' + что);
  } else {
    провалов++;
    console.log('  ✗ ПРОВАЛ: ' + что);
  }
}

/** Карта-заглушка: масть и достоинство не важны для конца партии, важна длина руки. */
function карта(имя) {
  return { масть: '♣', имя: имя, вес: игра.ВСЕ_ДОСТОИНСТВА.indexOf(имя) + 2 };
}

/**
 * Партия с пустой колодой и заданными руками по местам (индекс совпадает
 * с partия.игроки). Стол и пасы пусты — подхода, который надо разобрать,
 * нет, только сам вызов завершитьПодход доводит дело до проверитьКонец.
 */
function партияСРуками(настройки, руки) {
  const партия = игра.создатьПартию(настройки);
  партия.игроки.forEach(function (имя, i) {
    партия.руки[имя] = (руки[i] || []).map(карта);
  });
  партия.колода = [];
  партия.стол = [];
  партия.пасы = [];
  партия.берёт = false;
  партия.выбывшие = [];
  return партия;
}

/** Тот же путь, что в живой игре: конец подхода при пустой колоде решает всё. */
function доиграть(партия) {
  const сработало = игра.завершитьПодход(партия);
  проверить(сработало === true, 'завершитьПодход должен был сработать (партия ещё не завершена)');
  return партия;
}

/** Минимальный объект «комната» — ровно те поля, что читает застольеДляРейтинга. */
function мокКомната(партия) {
  const игроки = {};
  партия.игроки.forEach(function (имя, i) {
    игроки[имя] = { телеграм: 500000 + i, имя: 'Игрок ' + имя, этоБот: false, сдался: false };
  });
  return {
    мест: партия.игроки.length,
    парами: партия.парами === true,
    переводной: партия.переводной === true,
    игра: 'дурак',
    уровеньБотов: 3,
    игроки: игроки,
    партия: партия
  };
}

function застольеПоИмени(застолье, имя) {
  return застолье.find(function (строка) { return строка.имя === 'Игрок ' + имя; }) || null;
}

/* ---------------------------------------------------------------------
   1) Вдвоём: карты кончились у обоих сразу.
   --------------------------------------------------------------------- */
console.log('\n1) Вдвоём: колода пуста, руки пусты у обоих одновременно');
const вдвоём = доиграть(партияСРуками({ игроков: 2 }, [[], []]));
проверить(вдвоём.завершена === true, 'партия должна быть завершена');
проверить(вдвоём.результат === 'ничья', 'результат должен быть строкой «ничья», а не «' + вдвоём.результат + '»');
проверить(вдвоём.ничья === true, 'partия.ничья должна стать true при пустом списке проигравших');

const застольеВдвоём = комнаты.застольеДляРейтинга(мокКомната(вдвоём));
// Ноль найденного — тоже провал: застолье обязано вернуть ровно две строки.
проверить(застольеВдвоём.length === 2, 'рейтинг должен увидеть обе строки застолья, а увидел ' + застольеВдвоём.length);
вдвоём.игроки.forEach(function (имя) {
  const строка = застольеПоИмени(застольеВдвоём, имя);
  проверить(Boolean(строка) && строка.ничья === true && строка.победил === false,
    'место «' + имя + '»: ожидали ничья=true, победил=false, получили ' + JSON.stringify(строка));
});

/* ---------------------------------------------------------------------
   2) Парами: у обеих пар карт не осталось.
   --------------------------------------------------------------------- */
console.log('\n2) Парами: колода пуста, руки пусты у всех четверых');
const парами = доиграть(партияСРуками({ игроков: 4, парами: true }, [[], [], [], []]));
проверить(парами.парами === true, 'партия должна была собраться парной');
проверить(парами.завершена === true, 'парная партия должна быть завершена');
проверить(парами.результат === 'ничья', 'парная партия: результат должен быть «ничья», а не «' + парами.результат + '»');
проверить(парами.ничья === true, 'парная партия: partия.ничья должна стать true');

const застольеПарами = комнаты.застольеДляРейтинга(мокКомната(парами));
проверить(застольеПарами.length === 4, 'рейтинг должен увидеть все четыре строки застолья, а увидел ' + застольеПарами.length);
парами.игроки.forEach(function (имя) {
  const строка = застольеПоИмени(застольеПарами, имя);
  проверить(Boolean(строка) && строка.ничья === true && строка.победил === false,
    'парами, место «' + имя + '»: ожидали ничья=true, победил=false, получили ' + JSON.stringify(строка));
});

/* ---------------------------------------------------------------------
   3) Отрицательный случай: обычный конец, дурак один — ничьи тут нет.
   --------------------------------------------------------------------- */
console.log('\n3) Обычный конец: у одного из двоих осталась карта — дурак, не ничья');
const обычный = доиграть(партияСРуками({ игроков: 2 }, [['6'], []]));
проверить(обычный.завершена === true, 'обычная партия должна быть завершена');
проверить(обычный.ничья === false, 'partия.ничья должна остаться false, когда дурак есть, а стоит ' + обычный.ничья);
проверить(обычный.результат === обычный.проигравшие.join(' и '),
  'результат «' + обычный.результат + '» не сходится со списком проигравших ' + JSON.stringify(обычный.проигравшие));
проверить(обычный.проигравшие.length === 1, 'дурак должен быть ровно один, а их ' + обычный.проигравшие.length);

const застольеОбычный = комнаты.застольеДляРейтинга(мокКомната(обычный));
проверить(застольеОбычный.length === 2, 'обычный конец: рейтинг должен увидеть обе строки, а увидел ' + застольеОбычный.length);
обычный.игроки.forEach(function (имя) {
  const строка = застольеПоИмени(застольеОбычный, имя);
  const этоДурак = обычный.проигравшие.indexOf(имя) !== -1;
  проверить(Boolean(строка) && строка.ничья === false, 'обычный конец, место «' + имя + '»: ничья должна быть false');
  проверить(Boolean(строка) && строка.победил === !этоДурак,
    'обычный конец, место «' + имя + '»: победил должен быть ' + !этоДурак + ', получили ' + (строка && строка.победил));
});

/* ---------------------------------------------------------------------- */
console.log('');
console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
process.exit(провалов > 0 ? 1 : 0);
