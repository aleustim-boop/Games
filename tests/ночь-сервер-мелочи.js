/* ---------------------------------------------------------------------
   Ломающий запуск: копия server/ и js/ с одной порчей в сервер.js
   --------------------------------------------------------------------- */
function сделатьИспорченнуюКопию() {
  const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'ночь-сервер-копия-'));
  const данныеПроекта = path.join(КОРЕНЬ_ПРОЕКТА, 'server', 'данные');
  fs.cpSync(path.join(КОРЕНЬ_ПРОЕКТА, 'server'), path.join(врем, 'server'), {
    recursive: true,
    filter: function (откуда) { return откуда !== данныеПроекта && !откуда.startsWith(данныеПроекта + path.sep); }
  });
  require('./пути-проекта.js').скопироватьКод(КОРЕНЬ_ПРОЕКТА, врем, 'js');

  const файл = path.join(врем, 'server', 'сервер.js');
  let текст = fs.readFileSync(файл, 'utf8').replace(/\r\n/g, '\n');
  let было = '';
  let стало = '';
  if (ЛОМАТЬ_ИМЯ) {
    было = '  запомнитьИмяИзПодписи(кто, тело.initData);\n';
    стало = '  // ЛОМАЮЩИЙ ПРОГОН: подбор имя не запоминает\n';
  } else if (ЛОМАТЬ_ВРЕМЯ) {
    было = "  if (строка.мера === 'секунд' && значение < нижнийПределСекунд(строка, режим)) return null;\n";
    стало = '  // ЛОМАЮЩИЙ ПРОГОН: нижний предел времени не применяется\n';
  } else if (ЛОМАТЬ_ПИСЬМА) {
    было = '    if (строкаПисем) здоровье.турнирПисьма = строкаПисем;\n';
    стало = '    // ЛОМАЮЩИЙ ПРОГОН: поле «турнирПисьма» не отдаётся\n';
  }
  if (текст.split(было).length - 1 !== 1) {
    console.log('ЛОМАЮЩИЙ ЗАПУСК НЕ СОСТОЯЛСЯ: в копии server/сервер.js не найдено ровно одно место для порчи.');
    fs.rmSync(врем, { recursive: true, force: true });
    process.exit(2);
  }
  fs.writeFileSync(файл, текст.split(было).join(стало), 'utf8');
  return врем;
}

