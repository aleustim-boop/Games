/* ---------------------------------------------------------------------
   Подпись Telegram и разговор с сервером
   --------------------------------------------------------------------- */
function подписьИгрока(номер, имя) {
  const поля = {
    query_id: 'AAF' + номер,
    user: JSON.stringify({ id: номер, first_name: имя, username: 'igrok' + номер }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  const строки = Object.keys(поля).map(function (к) { return к + '=' + поля[к]; }).sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(ТОКЕН).digest();
  const hash = crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
  const сподписью = Object.assign({}, поля, { hash: hash });
  return Object.keys(сподписью)
    .map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(сподписью[к]); })
    .join('&');
}

/** Запрос к серверу. Долгий опрос подбора ждать не нужно: через 3 с идём дальше (код 0). */
function спросить(метод, путь, тело) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const заголовки = метод === 'POST'
      ? { 'Content-Type': 'application/json', 'Content-Length': данные.length } : {};
    const запрос = http.request({ host: ХОСТ, port: ПОРТ, path: encodeURI(путь), method: метод, headers: заголовки }, function (ответ) {
      let текст = '';
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (сбой) { разобрано = null; }
        готово({ код: ответ.statusCode, тело: разобрано || {}, текст: текст });
      });
    });
    запрос.setTimeout(3000, function () { готово({ код: 0, тело: {}, текст: '' }); запрос.destroy(); });
    запрос.on('error', function (сбой) { if (!запрос.destroyed) беда(сбой); });
    if (метод === 'POST') запрос.write(данные);
    запрос.end();
  });
}

function портСвободен(порт) {
  return new Promise(function (готово) {
    const проба = net.createServer();
    проба.once('error', function () { готово(false); });
    проба.once('listening', function () { проба.close(function () { готово(true); }); });
    проба.listen(порт, ХОСТ);
  });
}

