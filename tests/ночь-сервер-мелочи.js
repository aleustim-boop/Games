async function проверитьЗдоровьеПисьма() {
  console.log('4. /здоровье: окна писем турнира');
  /* Ближайший день, когда турнир вообще бывает (дни — настройка турниров). */
  let началоМс = 0;
  let конецДоигрышаМс = 0;
  const сегодня = Date.now();
  for (let д = 0; д < 14 && !началоМс; д++) {
    const день = турниры.турнирДня(сегодня + д * 24 * 60 * МИНУТА);
    if (день.состояние !== 'нет турнира') {
      началоМс = день.началоМс;
      конецДоигрышаМс = день.конецМс + турниры.НАСТРОЙКИ.доигрышМин * МИНУТА;
    }
  }
  проверить(началоМс > 0, 'опора: нашёлся день с турниром в ближайшие две недели');
  if (!началоМс) return;

  const рано = await здоровьеВМомент(началоМс - 30 * МИНУТА);
  проверить(рано.живой === true && рано.турнирПисьма === undefined, 'за 30 минут до начала поля «турнирПисьма» нет (' + JSON.stringify(рано) + ')');
  const напоминания = await здоровьеВМомент(началоМс - 5 * МИНУТА);
  проверить(напоминания.турнирПисьма === 'идут напоминания', 'за 5 минут до начала: «идут напоминания» (' + напоминания.турнирПисьма + ')');
  const идёт = await здоровьеВМомент(началоМс + 5 * МИНУТА);
  проверить(идёт.турнирПисьма === undefined, 'пока идут пары письма не идут: поля нет (' + идёт.турнирПисьма + ')');
  const итог = await здоровьеВМомент(конецДоигрышаМс + 5 * МИНУТА);
  проверить(итог.турнирПисьма === 'идёт итог', 'через 5 минут после окончания доигрыша: «идёт итог» (' + итог.турнирПисьма + ')');
  const поздно = await здоровьеВМомент(конецДоигрышаМс + 90 * МИНУТА);
  проверить(поздно.турнирПисьма === undefined, 'через полтора часа после окончания поля нет (' + поздно.турнирПисьма + ')');
  сервера.оснасткаТурнира();
}

