/* ---------------------------------------------------------------------
   Перехват настоящего Telegram: любой запрос в api.telegram.org считается
   и обрывается, в сеть не уходит.
   --------------------------------------------------------------------- */
const настоящийЗапрос = https.request;
let запросовВTelegram = 0;
https.request = function (настройки) {
  const куда = настройки && typeof настройки === 'object' ? String(настройки.hostname || настройки.host || '') : String(настройки || '');
  if (куда.indexOf('api.telegram.org') === -1) return настоящийЗапрос.apply(https, arguments);
  запросовВTelegram++;
  const подделка = new EventEmitter();
  подделка.setTimeout = function () { return подделка; };
  подделка.write = function () { return true; };
  подделка.destroy = function () { return подделка; };
  подделка.end = function () {
    setImmediate(function () { подделка.emit('error', new Error('перехвачено проверкой')); });
    return подделка;
  };
  return подделка;
};

