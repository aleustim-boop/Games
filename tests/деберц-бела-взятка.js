'use strict';
const assert = require('node:assert/strict');
const П = require('../js/деберц-правила.js');
const И = require('../server/игры/деберц.js');
const к = (имя, масть = '♠') => ({ id: масть + имя, имя, масть });
for (const режим of ['2', '3', '4', '2x2']) for (const первая of ['Д', 'К']) {
  const n = режим === '2x2' ? 4 : +режим;
  for (let победитель = 0; победитель < n; победитель++) {
    const и = П.создать(Math.random, 301, true, режим);
    Object.assign(и, { фаза: 'игра', козырь: '♠', заказчик: 0, ход: 0 });
    и.руки = Array.from({ length: n }, (_, i) => i === 0 ? [к(первая), к(первая === 'Д' ? 'К' : 'Д')]
      : [победитель === i ? к('В') : к(['7', '8', '9'][i - 1], '♥'), к(['7', '8', '9'][i - 1], '♦')]);
    и.белла[0] = true;
    for (let i = 0; i < n; i++) П.сыграть(и, i, и.руки[i][0].id);
    assert.equal(и.очки[0], 0); assert.equal(и.белаСтатус[0], 'ждёт');
    assert.equal(П.старшаяКарта(и).игрок, победитель);
    const сумма = и.стол.reduce((s, x) => s + П.очки(x.карта, и.козырь), 0);
    const заслужена = победитель === 0 || режим === '2x2' && победитель === 2;
    П.забрать(и);
    assert.equal(и.белаСтатус[0], заслужена ? 'засчитана' : 'проиграна');
    assert.equal(и.очки.reduce((s, x) => s + x, 0), сумма + (заслужена ? 20 : 0));
    const п = { игра: и, игроки: Array.from({ length: n }, (_, i) => 'игрок' + i), проигравшие: [], завершена: false };
    assert.equal(И.видДляИгрока(п, 'игрок1').деберц.белаСтатус[n - 1], и.белаСтатус[0]);
    while (и.фаза === 'игра') П.сыграть(и, и.ход, П.доступные(и, и.ход)[0].id);
    const сумма2 = и.стол.reduce((s, x) => s + П.очки(x.карта, и.козырь), 0);
    П.забрать(и);
    assert.equal(и.очки.reduce((s, x) => s + x, 0), сумма + сумма2 + 10 + (заслужена ? 20 : 0), 'Вторая карта не повторяет и не возвращает белу');
  }
}
// Сохранённые журналы версии 4 не пересчитываются по новым правилам.
const старая = П.создать(Math.random, 301, true, '2', 4);
Object.assign(старая, { фаза: 'игра', козырь: '♠', ход: 0, руки: [[к('Д'), к('К')], [к('В')]], белла: [true, false] });
П.сыграть(старая, 0, '♠Д'); assert.equal(старая.очки[0], 20);
