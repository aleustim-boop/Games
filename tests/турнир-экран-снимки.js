let проверок = 0;
let провалов = 0;
function надо(условие, слова) {
  проверок++;
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}

function поднятьСервер() {
  return new Promise((готово) => {
    const сервер = http.createServer((запрос, ответ) => {
      let путь = '/';
      try { путь = decodeURIComponent(запрос.url.split('?')[0]); } catch (о) { /* как есть */ }
      if (путь.slice(-1) === '/') путь += 'index.html';
      const файл = path.join(КОРЕНЬ, путь);
      if (файл.indexOf(КОРЕНЬ) !== 0 || !fs.existsSync(файл) || fs.statSync(файл).isDirectory()) {
        ответ.writeHead(404); ответ.end('нет'); return;
      }
      ответ.writeHead(200, { 'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'application/octet-stream' });
      ответ.end(fs.readFileSync(файл));
    });
    сервер.listen(0, '127.0.0.1', () => готово(сервер));
  });
}

async function прогнатьОдно(браузер, адрес, с, ширина) {
  const ошибки = [];
  const страница = await браузер.newPage({ viewport: { width: ширина, height: 844 } });
  await безTelegram(страница);
  страница.on('console', (з) => {
    const откуда = (з.location && з.location().url) || '';
    if (з.type() === 'error' && откуда.indexOf('telegram-web-app.js') !== -1) return;
    if (з.type() === 'error') ошибки.push(з.text() + (откуда ? ' @ ' + откуда : ''));
  });
  страница.on('pageerror', (о) => ошибки.push('pageerror: ' + (о && о.message)));
  await перехватить(страница, /^http:\/\/127\.0\.0\.1:8790\//, (п) =>
    п.fulfill({ status: 200, contentType: 'application/json; charset=utf-8', body: JSON.stringify({ ок: false }) }));
  await страница.goto(адрес);
  await страница.waitForFunction(() => window.Сеть && window.ТурнирЭкран && document.getElementById('приложение'));
  await страница.waitForTimeout(500);
  // Заглушки подменяем после загрузки; в «ломающем» запуске отдаём «идёт» вместо нужного.
  const отдаваемый = СЛОМАТЬ ? СОСТОЯНИЯ.find((х) => х.имя === 'идёт') : с;
  await страница.evaluate((в) => {
    window.Сеть.турнир = () => Promise.resolve({ ок: true, вид: в });
    window.Сеть.турнирЗаписаться = () => Promise.resolve({ ок: true, вид: Object.assign({}, в, { записан: true }) });
    window.Сеть.ждатьТурнир = () => new Promise(() => {});
    window.Сеть.броситьТурнир = () => {};
    window.ТурнирЭкран.открыть();
  }, отдаваемый.вид());
  await страница.waitForTimeout(600);
  const факт = await страница.evaluate(() => {
    function видимыйТекст(селектор) {
      const н = document.querySelector(селектор);
      if (!н || н.classList.contains('скрыт') || н.getBoundingClientRect().height === 0) return '';
      return н.textContent;
    }
    const э = document.getElementById('экран-турнир');
    const р = document.documentElement;
    const виден = !!э && э.classList.contains('экран--виден') && э.getBoundingClientRect().width > 0;
    return {
      найден: э ? 1 : 0, виден: виден,
      состояние: э ? э.getAttribute('data-состояние') : null,
      строк: document.querySelectorAll('#экран-турнир .турнир-строка').length,
      подсказка: видимыйТекст('#экран-турнир .турнир-подсказка'),
      правило: видимыйТекст('#экран-турнир .турнир-правило'),
      подписи: Array.from(document.querySelectorAll('#экран-турнир .турнир-подписи:not(.скрыт) > span')).map((н) => н.textContent),
      подписиВсего: document.querySelectorAll('#экран-турнир .турнир-подписи').length,
      левыеКолонки: (function () {
        const п = document.querySelector('#экран-турнир .турнир-подписи:not(.скрыт) .турнир-очки');
        const с = document.querySelector('#экран-турнир .турнир-строка .турнир-очки');
        return п && с ? [Math.round(п.getBoundingClientRect().right), Math.round(с.getBoundingClientRect().right)] : null;
      })(),
      моих: document.querySelectorAll('#экран-турнир .турнир-строка--я').length,
      шир: р.scrollWidth, вид: р.clientWidth, телоШир: document.body.scrollWidth
    };
  });
  const метка = с.имя + ' @' + ширина;
  надо(факт.найден === 1, метка + ': узел #экран-турнир найден (найдено: ' + факт.найден + ')');
  надо(факт.виден, метка + ': экран турнира виден');
  надо(факт.состояние === с.ждём, метка + ': data-состояние «' + факт.состояние + '», ждали «' + с.ждём + '»');
  if (с.ждём === 'идёт') {
    const ждуСтрок = с.строк || 5;
    надо(факт.строк === ждуСтрок, метка + ': строк таблицы ' + факт.строк + ', ждали ' + ждуСтрок);
    надо(факт.моих === 1, метка + ': строк «я» ровно одна (их ' + факт.моих + ')');
    надо(факт.подсказка === 'Партия начнётся сама — не закрывайте экран', метка + ': видна подсказка ожидания («' + факт.подсказка + '»)');
    надо(факт.правило === 'Победа — 2 очка, ничья — 1, поражение — 0', метка + ': видно правило очков («' + факт.правило + '»)');
    надо(факт.подписиВсего === 1 && факт.подписи.join('|') === '|Игрок|Партий|Очки', метка + ': подписи колонок (узлов ' + факт.подписиВсего + ', текст «' + факт.подписи.join('|') + '»)');
    надо(!!факт.левыеКолонки && Math.abs(факт.левыеКолонки[0] - факт.левыеКолонки[1]) <= 1, метка + ': «Очки» стоят над очками (правые края ' + JSON.stringify(факт.левыеКолонки) + ')');
  } else {
    надо(факт.подсказка === '', метка + ': подсказки ожидания нет');
  }
  const ширинаМакс = Math.max(факт.шир, факт.телоШир);
  надо(ширинаМакс <= факт.вид, метка + ': нет горизонтальной прокрутки (' + ширинаМакс + ' ≤ ' + факт.вид + ')');
  надо(ошибки.length === 0, метка + ': ошибок консоли ' + ошибки.length + (ошибки.length ? ' — ' + ошибки.join(' | ') : ''));
  const файл = path.join(ПАПКА, 'турнир-' + с.имя + '-' + ширина + '.png');
  await страница.screenshot({ path: файл });
  надо(fs.existsSync(файл) && fs.statSync(файл).size > 1000, метка + ': снимок записан ' + файл);
  await страница.close();
}

(async () => {
  const список = СОСТОЯНИЯ.filter((с) => !ТОЛЬКО || с.имя === ТОЛЬКО);
  надо(список.length > 0, 'выбрано состояний: ' + список.length + (ТОЛЬКО ? ' (--только=' + ТОЛЬКО + ')' : ''));
  fs.mkdirSync(ПАПКА, { recursive: true });
  const сервер = await поднятьСервер();
  const адрес = 'http://127.0.0.1:' + сервер.address().port + '/index.html';
  const браузер = await chromium.launch();
  try {
    for (const с of список) for (const ш of ШИРИНЫ) await прогнатьОдно(браузер, адрес, с, ш);
  } catch (о) {
    надо(false, 'прогон упал: ' + (о && о.message));
  } finally {
    await браузер.close();
    сервер.close();
  }
  console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);
  process.exit(провалов === 0 ? 0 : 1);
})();
