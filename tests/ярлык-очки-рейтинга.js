'use strict';

/* Проверка: ОчкиРейтинга.сдать (партия с ботом настольных игр) сообщает
   общее/js/ярлык.js, что партия сыграна — с именем игры, под которое брали билет.
   Файл гоняем в песочнице vm с подменой window.

   Запуск:  node tests/ярлык-очки-рейтинга.js [путь-к-файлу]
   (по умолчанию общее/js/очки-рейтинга.js)
   Ломающий запуск: путь к КОПИИ файла без строки с window.Ярлык — проверка
   обязана покраснеть. Настоящий файл не портим. */

const fs = require('fs');
const vm = require('vm');
const path = require('path');

const КОРЕНЬ = path.resolve(__dirname, '..');
const аргумент = process.argv.slice(2).find(function (а) { return !а.startsWith('--'); });
const ПУТЬ = аргумент ? path.resolve(аргумент) : path.join(КОРЕНЬ, 'общее', 'js', 'очки-рейтинга.js');
const ИСХОДНИК = fs.readFileSync(ПУТЬ, 'utf8');

let всего = 0;
let провалов = 0;
function проверить(что, правда) {
  всего++;
  if (!правда) провалов++;
  console.log((правда ? '  ок   ' : '  БЕДА ') + что);
}

/** Мир: window с (по желанию) шпионом Ярлык и без Telegram — сеть не нужна. */
function мир(сЯрлыком) {
  const вызовы = [];
  const окно = {};
  if (сЯрлыком) окно.Ярлык = { партияСыграна: function (игра) { вызовы.push(игра); } };
  const песочница = { window: окно, console: console, Promise: Promise, setTimeout: setTimeout, clearTimeout: clearTimeout };
  vm.createContext(песочница);
  vm.runInContext(ИСХОДНИК, песочница, { filename: ПУТЬ });
  return { Очки: окно.ОчкиРейтинга, вызовы: вызовы };
}

async function главная() {
  const м = мир(true);
  проверить('ОчкиРейтинга загрузился и есть сдать', !!м.Очки && typeof м.Очки.сдать === 'function');

  for (const игра of ['нарды', 'шахматы', 'домино']) {
    const ручка = м.Очки.взятьБилет(игра, 'обычный');
    await м.Очки.сдать(ручка, 'победа');
    проверить('сдать зовёт Ярлык.партияСыграна(\'' + игра + '\')', м.вызовы[м.вызовы.length - 1] === игра);
  }
  проверить('три сдачи — ровно три вызова', м.вызовы.length === 3);

  // Повторная сдача той же ручки (она уже сдана) — не новая партия.
  const ручка = м.Очки.взятьБилет('нарды', 'обычный');
  await м.Очки.сдать(ручка, 'победа');
  const было = м.вызовы.length;
  await м.Очки.сдать(ручка, 'победа');
  проверить('повторная сдача той же ручки не считается', м.вызовы.length === было);

  // Нет ручки — партии нет.
  const до = м.вызовы.length;
  await м.Очки.сдать(null, 'победа');
  проверить('сдать без ручки не считает партию', м.вызовы.length === до);

  // Страница без общее/js/ярлык.js — молча, без падения.
  const без = мир(false);
  let упало = false;
  try { await без.Очки.сдать(без.Очки.взятьБилет('нарды', 'обычный'), 'победа'); } catch (_) { упало = true; }
  проверить('без window.Ярлык сдать не падает', !упало);

  console.log('Итого проверок: ' + всего + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
}

главная();
