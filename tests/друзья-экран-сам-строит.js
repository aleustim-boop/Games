/* =====================================================================
   ЭКРАН ДРУЗЕЙ СТРОИТ СЕБЯ САМ (этап Ф2 плана штаб/план-друзья-везде.md)

   Зачем. общее/js/друзья-экран.js подключат на всех страницах сборника, а
   разметка «Мои друзья» / «Добавить друга» есть только в index.html.
   Модуль при первом открытии обязан построить оба экрана сам — и не
   делать второй копии там, где разметка уже есть.

   Браузера нет: модуль поднимается в поддельном браузере
   (tests/поддельный-браузер.js), window.Сеть — подделка.

   Случаи:
     1. Страница без разметки: до открытия экранов нет; после открыть()
        есть оба (в #приложение), по одному; устройство — то же, что в
        index.html (теги, id, классы, слова — читаем из самого index.html);
        «Добавить друга» и оба «Назад» живые; выключатель с подписью
        «Показывать, что я в сети»; друг на связи — метка «в сети»
        и кнопка «Позвать»; второе открытие копии не строит.
     2. Страница с готовой разметкой (разобрана из index.html): после
        открыть() ровно один #экран-друзей и один #экран-добавить-друга,
        это те же узлы, кнопки привязаны.
     3. разборПрисутствия (модуль в Node) даёт «в сети».

   Запуск:
     node tests/друзья-экран-сам-строит.js                — проверить проект
     node tests/друзья-экран-сам-строит.js --файл=<путь>  — проверить копию
     node tests/друзья-экран-сам-строит.js --сломать      — ломающий запуск:
         копия модуля во временной папке без постройки разметки, проверка
         на ней обязана покраснеть на «нет #экран-друзей». Файл проекта
         не трогается.
   ===================================================================== */

