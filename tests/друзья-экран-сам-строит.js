function подождать() {
  return new Promise(function (готово) { setTimeout(готово, 20); });
}

/* ---------------------------------------------------------------------
   Разметка из index.html — единственный образец устройства экранов.
   Маленький разборщик: только открывающие/закрывающие теги и текст,
   этого хватает для двух секций экрана друзей.
   --------------------------------------------------------------------- */

function вырезатьСекцию(html, id) {
  const найдено = html.match(new RegExp('<section id="' + id + '"[\\s\\S]*?</section>'));
  return найдено ? найдено[0] : '';
}

function атрибут(строка, имя) {
  const н = строка.match(new RegExp(имя + '="([^"]*)"'));
  return н ? н[1] : '';
}

/** Собрать из куска html узлы поддельного документа. Возвращает корневой узел. */
function разобрать(html, документ) {
  const стек = [документ.createElement('div')];
  const образец = /<(\/?)([a-z0-9]+)([^>]*)>|([^<]+)/gi;
  let н;
  while ((н = образец.exec(html)) !== null) {
    const верх = стек[стек.length - 1];
    if (н[4] !== undefined) {
      const текст = н[4].trim();
      if (текст) верх.appendChild(документ.createTextNode(текст));
    } else if (н[1] === '/') {
      стек.pop();
    } else {
      const у = документ.createElement(н[2]);
      const id = атрибут(н[3], 'id');
      const класс = атрибут(н[3], 'class');
      const тип = атрибут(н[3], 'type');
      if (id) у.id = id;
      if (класс) у.className = класс;
      if (тип) у.type = тип;
      верх.appendChild(у);
      стек.push(у);
    }
  }
  return стек[0].firstElementChild;
}

/** Устройство экрана строками «тег#id.класс:слова» — для сравнения с образцом. */
function устройство(узел, итог) {
  const список = итог || [];
  if (!узел || узел.nodeType !== 1) return список;
  if (УЗЛЫ_ВЫКЛЮЧАТЕЛЯ.indexOf(узел.id) !== -1) return список;
  const слова = узел.childNodes.filter(function (д) { return д.nodeType === 3; })
    .map(function (д) { return д.textContent.trim(); }).join(' ');
  // «экран--виден» — состояние, а не устройство: его ставит показ экрана.
  const класс = узел.className.split(/\s+/).filter(function (к) { return к && к !== 'экран--виден'; }).join(' ');
  список.push(String(узел.tagName || узел.nodeName).toLowerCase() + '#' + (узел.id || '') +
    '.' + класс +(узел.type ? '[' + узел.type + ']' : '') + ':' + слова);
  узел.childNodes.forEach(function (д) { устройство(д, список); });
  return список;
}

/** Все узлы документа с данным id — считаем копии, getElementById отдаёт одну. */
function всеСId(документ, id) {
  const найдено = [];
  (function обойти(у) {
    if (у.id === id) найдено.push(у);
    (у.childNodes || []).forEach(обойти);
  })(документ.documentElement);
  return найдено;
}

/* ---------------------------------------------------------------------
   Поднять модуль в поддельном браузере с подделкой window.Сеть
   --------------------------------------------------------------------- */

function поднятьЭкран(исходник, готоваяРазметка) {
  const документ = бр.сделатьДокумент();
  const приложение = документ.createElement('div');
  приложение.id = 'приложение';
  документ.body.appendChild(приложение);
  // Экран, откуда пришли: «Назад» из друзей обязан вернуть сюда.
  const лобби = документ.createElement('section');
  лобби.id = 'экран-лобби';
  лобби.className = 'экран экран--виден';
  приложение.appendChild(лобби);
  готоваяРазметка.forEach(function (секция) { приложение.appendChild(секция(документ)); });

  const поднятый = бр.поднять(исходник, { документ: документ, имяФайла: 'общее/js/друзья-экран.js' });
  const счёт = { список: 0, онлайн: 0, знакомые: 0 };
  поднятый.окно.Сеть = {
    друзьяСписок: function () {
      счёт.список++;
      return Promise.resolve({ беда: null, данные: { узналиВас: true, друзья: [{ ключ: 'б1', имя: 'Боря' }], входящие: [] } });
    },
    друзьяОнлайн: function () {
      счёт.онлайн++;
      return Promise.resolve({ беда: null, данные: { узналиВас: true, меняВидно: true, друзья: [{ ключ: 'б1', наСвязи: true }] } });
    },
    списокЗнакомых: function () {
      счёт.знакомые++;
      return Promise.resolve({ знакомые: [], свежий: true });
    },
    позватьЗнакомого: function () { return Promise.resolve({ ок: true, словами: 'Позвали' }); }
  };
  поднятый.приложение = приложение;
  поднятый.счёт = счёт;
  return поднятый;
}

function виден(документ, id) {
  const у = документ.getElementById(id);
  return Boolean(у) && у.classList.contains('экран--виден');
}

/** Нажать «Назад» с «Моих друзей»: останавливает опрос, таймер не держит процесс. */
function закрыть(поднятый) {
  const назад = поднятый.документ.getElementById('кнопка-друзья-назад');
  if (назад) назад.click();
}

