'use strict';
/* Снимки и сверки страницы «доска Кодекса» и блока «Задачи Кодексу» на дашборде штаба.
   Снимки — в tests/снимки/кодекс/. Настоящую доску штаб/кодекс-задачи.json скрипт не трогает:
   наполненная доска делается во временной папке и отдаётся своим маленьким сервером.
   Запуск: node tests/дашборд-кодекс-снимки.js  (дашборд должен работать на 8791).
   Перед запуском: node штаб/браузер-занят.js --ждать */

const fs = require('fs');
const os = require('os');
const path = require('path');
const http = require('http');
const { chromium } = require('./браузер-робот');
const сбор = require('../штаб/сбор.js');
const кодексСтраница = require('../штаб/кодекс-страница.js');

const ДАШБОРД = process.env.ДАШБОРД || 'http://127.0.0.1:8791';
const ПАПКА = path.join(__dirname, 'снимки', 'кодекс');

let проверок = 0;
let провалов = 0;
function сверка(название, ок, подробность) {
  проверок++;
  if (!ок) провалов++;
  console.log((ок ? 'ХОРОШО  ' : 'ПРОВАЛ  ') + название + (подробность ? ' — ' + подробность : ''));
}

function придуманнаяДоска() {
  const з = (ключ, статус, что, куда, ещё) => Object.assign({
    ключ, игра: 'Дурак', статус, что, размер: '512x512', формат: 'png', куда: куда || 'img/дурак/рубашка.png',
    поставил: 'Джо', поставлено: '2026-09-30T09:00'
  }, ещё || {});
  return {
    задачи: [
      з('к-1', 'ждёт', 'Нарисовать рубашку карты'),
      з('к-2', 'в работе', 'Нарисовать очень длинное название задачи, которое обязательно не влезет в одну строку на узком экране телефона и должно красиво перенестись на следующие строки без ползунка', null, { взято: '2026-09-30T10:00' }),
      з('к-3', 'сдано', 'Фон стола', null, { взято: '2026-09-30T10:00', сдано: '2026-09-30T11:00' }),
      з('к-4', 'сдано', 'Значок козыря', 'img/дурак/очень/длинный/путь/который/никак/не/разбивается/на/слова/и/должен/переноситься/без/горизонтальной/прокрутки/козырь-значок-большой-версии-финальный.png', { сдано: '2026-09-30T11:30' }),
      з('к-5', 'вернули', 'Лицо короля', null, { замечания: [{ когда: '2026-09-30T12:00', кто: 'владелец', текст: 'Корона слишком тёмная, сделай светлее' }] }),
      з('к-6', 'принято', 'Рамка профиля', null, { принято: '2026-09-29T18:00' }),
      з('к-7', 'принято', 'Иконка звука', null, { принято: '2026-09-30T08:00' })
    ]
  };
}

(async () => {
  fs.mkdirSync(ПАПКА, { recursive: true });
  const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'кодекс-доска-'));
  const файлДоски = path.join(врем, 'доска.json');
  const придуманная = придуманнаяДоска();
  // Ломающий запуск: портится только копия во временной папке (одна задача пропадает) — проверка «ровно 7» обязана покраснеть
  if (process.argv.includes('--сломать')) придуманная.задачи.pop();
  fs.writeFileSync(файлДоски, JSON.stringify(придуманная));
  const доска = сбор.собратьКодекс(файлДоски);
  const html = кодексСтраница.страница(доска);
  const сервер = http.createServer((q, о) => { о.writeHead(200, { 'content-type': 'text/html; charset=utf-8' }); о.end(html); });
  await new Promise(р => сервер.listen(0, '127.0.0.1', р));
  const своё = 'http://127.0.0.1:' + сервер.address().port + '/';
  console.log('Свой сервер: ' + своё + ' (порт ' + сервер.address().port + ', PID ' + process.pid + ')');

  const браузер = await chromium.launch();
  const ошибки = [];
  try {
    for (const ширина of [390, 1280]) {
      for (const тема of ['light', 'dark']) {
        const имяТемы = тема === 'light' ? 'светлая' : 'тёмная';
        const контекст = await браузер.newContext({ viewport: { width: ширина, height: 844 }, colorScheme: тема });
        const стр = await контекст.newPage();
        стр.on('console', м => { if (м.type() === 'error') ошибки.push(ширина + '/' + тема + ': ' + м.text()); });
        стр.on('pageerror', е => ошибки.push(ширина + '/' + тема + ' pageerror: ' + е.message));
        const метка = ширина + '-' + имяТемы;
        const без = ширина === 390;

        // А) пустая доска с работающего дашборда
        await стр.goto(ДАШБОРД + '/' + encodeURIComponent('кодекс'), { waitUntil: 'domcontentloaded' });
        await стр.waitForTimeout(600);
        const текстП = await стр.evaluate(() => document.body.innerText);
        if (ширина === 390 && тема === 'light') {
          сверка('пустая доска: есть фраза для Кодекса', текстП.includes('Прочитай штаб/кодексу.md и сделай задачи с доски'));
        }
        if (без) {
          const с = await стр.evaluate(() => [document.documentElement.scrollWidth, window.innerWidth]);
          сверка('пустая доска ' + имяТемы + ': нет горизонтальной прокрутки', с[0] <= с[1], 'scrollWidth ' + с[0] + ', окно ' + с[1]);
        }
        await стр.screenshot({ path: path.join(ПАПКА, 'пустая-' + метка + '.png'), fullPage: true });

        // Б) наполненная доска
        await стр.goto(своё, { waitUntil: 'domcontentloaded' });
        await стр.waitForTimeout(600);
        if (ширина === 390 && тема === 'light') {
          const задач = await стр.locator('li.кодекс-задача').count();
          сверка('наполненная доска: ровно 7 задач', задач === 7, 'найдено ' + задач);
          const порядок = await стр.evaluate(() => {
            const р = [];
            document.querySelectorAll('li.кодекс-задача').forEach(li => {
              const к = [...li.classList].find(c => c.startsWith('кодекс--'));
              if (р[р.length - 1] !== к) р.push(к);
            });
            return р;
          });
          const ждём = ['кодекс--сдано', 'кодекс--вернули', 'кодекс--работа', 'кодекс--ждёт', 'кодекс--принято'];
          сверка('наполненная доска: порядок групп сдано, вернули, в работе, ждёт, принято',
            JSON.stringify(порядок) === JSON.stringify(ждём), порядок.join(' > '));
          сверка('наполненная доска: есть фраза для Кодекса', (await стр.evaluate(() => document.body.innerText)).includes('Прочитай штаб/кодексу.md и сделай задачи с доски'));
        }
        // раскрываем «Принято», чтобы снимок показал и её
        await стр.evaluate(() => document.querySelectorAll('details').forEach(д => { д.open = true; }));
        if (без) {
          const с = await стр.evaluate(() => [document.documentElement.scrollWidth, window.innerWidth]);
          сверка('наполненная доска ' + имяТемы + ': нет горизонтальной прокрутки', с[0] <= с[1], 'scrollWidth ' + с[0] + ', окно ' + с[1]);
        }
        await стр.screenshot({ path: path.join(ПАПКА, 'наполненная-' + метка + '.png'), fullPage: true });

        // В) главная, блок #даш-кодекс с соседями
        await стр.goto(ДАШБОРД + '/', { waitUntil: 'domcontentloaded' });
        await стр.waitForTimeout(800);
        const блок = стр.locator('#даш-кодекс');
        const есть = await блок.count();
        сверка('главная ' + метка + ': найден раздел #даш-кодекс', есть === 1, 'найдено ' + есть);
        if (есть) {
          if (ширина === 390 && тема === 'light') {
            const ссылок = await стр.locator('#даш-кодекс a[href="/кодекс"]').count() + await стр.locator('#даш-кодекс a[href="/%D0%BA%D0%BE%D0%B4%D0%B5%D0%BA%D1%81"]').count();
            сверка('главная: в #даш-кодекс есть ссылка на /кодекс', ссылок > 0, 'найдено ' + ссылок);
            const навиг = await стр.locator('nav.даш-навигация a', { hasText: 'Кодекс' }).count();
            сверка('главная: в навигации есть ссылка «Кодекс»', навиг === 1, 'найдено ' + навиг);
            const кнопка = await стр.locator('[data-dashboard-theme]').count();
            сверка('главная: есть кнопка темы', кнопка === 1, 'найдено ' + кнопка);
          }
          if (без) {
            const с = await стр.evaluate(() => [document.documentElement.scrollWidth, window.innerWidth]);
            сверка('главная ' + имяТемы + ': нет горизонтальной прокрутки', с[0] <= с[1], 'scrollWidth ' + с[0] + ', окно ' + с[1]);
          }
          // Кадр 1: верх страницы — шапка и строка разделов
          await стр.evaluate(() => window.scrollTo(0, 0));
          await стр.waitForTimeout(200);
          const навСтр = await стр.evaluate(() => {
            const н = document.querySelector('nav.даш-навигация');
            if (!н) return null;
            const р = н.getBoundingClientRect();
            const ссылка = [...н.querySelectorAll('a')].find(а => а.textContent.trim() === 'Кодекс');
            const с = ссылка ? ссылка.getBoundingClientRect() : null;
            return {
              низ: р.bottom, окно: window.innerHeight, ширинаОкна: window.innerWidth,
              стр: document.documentElement.scrollWidth,
              ссылка: с ? { w: с.width, h: с.height, право: с.right, лево: с.left } : null
            };
          });
          сверка('главная ' + метка + ': строка разделов найдена', !!навСтр);
          if (навСтр) {
            сверка('главная ' + метка + ': строка разделов целиком в кадре верха', навСтр.низ <= навСтр.окно, 'низ ' + Math.round(навСтр.низ) + ', высота окна ' + навСтр.окно);
            сверка('главная ' + метка + ': ссылка «Кодекс» видима (ширина и высота больше нуля)', !!навСтр.ссылка && навСтр.ссылка.w > 0 && навСтр.ссылка.h > 0);
            if (ширина === 1280) {
              сверка('главная ' + метка + ': ссылка «Кодекс» не выходит за правый край окна', !!навСтр.ссылка && навСтр.ссылка.право <= навСтр.ширинаОкна, навСтр.ссылка ? 'правый край ' + Math.round(навСтр.ссылка.право) : '');
            }
            if (без) {
              сверка('главная ' + метка + ': строка разделов не даёт горизонтальной прокрутки страницы', навСтр.стр <= навСтр.ширинаОкна, 'scrollWidth ' + навСтр.стр + ', окно ' + навСтр.ширинаОкна);
            }
          }
          await стр.screenshot({ path: path.join(ПАПКА, 'главная-верх-' + метка + '.png') });

          // Кадр 2: раздел «Кодекс» по центру окна
          await стр.evaluate(() => document.querySelector('#даш-кодекс').scrollIntoView({ block: 'center' }));
          await стр.waitForTimeout(300);
          const б = await стр.evaluate(() => {
            const р = document.querySelector('#даш-кодекс').getBoundingClientRect();
            return { верх: р.top, низ: р.bottom, окно: window.innerHeight };
          });
          сверка('главная ' + метка + ': #даш-кодекс после прокрутки целиком в окне', б.верх >= 0 && б.низ <= б.окно, 'верх ' + Math.round(б.верх) + ', низ ' + Math.round(б.низ) + ', высота окна ' + б.окно);
          await стр.screenshot({ path: path.join(ПАПКА, 'главная-кодекс-' + метка + '.png') });
        }
        await контекст.close();
      }
    }
  } finally {
    await браузер.close();
    сервер.close();
  }
  сверка('в консоли браузера нет ошибок', ошибки.length === 0, ошибки.length ? ошибки.slice(0, 5).join(' | ') : '');
  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
})().catch(е => { console.log('ПАДЕНИЕ: ' + (е && е.stack || е)); process.exit(1); });
