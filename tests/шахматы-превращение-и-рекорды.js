'use strict';

/* =====================================================================
   ШАХМАТЫ: ПРЕВРАЩЕНИЕ ПЕШКИ И РЕКОРДЫ.

   Два места, которых не видел никто:

     1. ПЛАШКА ПРЕВРАЩЕНИЯ — четыре крупные кнопки, их не нажимал пальцем
        ни один человек. Пешку доводим до края по-настоящему, играя вдвоём
        за обе стороны;
     2. РЕКОРДЫ — они у шахмат появились только что: серия побед подряд
        против робота, отдельно по уровням. Смотрим таблицу на 320 точках
        и строку серии на плашке итога.

   Отдельно проверяем тонкость: НИЧЬЯ СЕРИЮ НЕ РВЁТ И НЕ РАСТИТ.
   В шахматах ничья сплошь и рядом лучшее, что есть в позиции, и считать
   её поражением значило бы наказывать за правильную игру.

   Запуск (страничный сервер уже поднят):
       node tests/шахматы-превращение-и-рекорды.js 8080
   ===================================================================== */

const { chromium, подготовитьПодделку } = require('./браузер-робот.js');

const ПОРТ = Number(process.argv[2]) || 8080;
const АДРЕС = 'http://127.0.0.1:' + ПОРТ + '/шахматы.html';
const ПАПКА = 'tests/скриншоты/';

let провалов = 0;
function проверить(условие, слова) {
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}
const спать = (мс) => new Promise((ф) => setTimeout(ф, мс));

async function новая(браузер, ш, в) {
  const окно = await браузер.newContext({ viewport: { width: ш, height: в }, hasTouch: true, deviceScaleFactor: 2 });
  const страница = await окно.newPage();
  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
    красные.push('консоль: ' + м.text());
  });
  await подготовитьПодделку(страница, { версия: '8.0', полныйЭкран: 'дают' });
  await страница.goto(АДРЕС);
  await спать(700);
  return { окно, страница, красные };
}

(async () => {
  console.log('Шахматы: превращение и рекорды. Страница: ' + АДРЕС);
  const браузер = await chromium.launch();

  /* ================================================================
     1. Доводим пешку до края
     ================================================================ */
  console.log('\n=== Превращение пешки ===');
  {
    const { окно, страница, красные } = await новая(браузер, 390, 844);
    await страница.click('#кнопка-вдвоём');
    await спать(700);

    /* Ходим за ОБЕ стороны и гоним пешки вперёд. Раньше я выбирал
       «самый верхний подсвеченный ход» — для чёрных это ход назад,
       и до края не доходил никто. Теперь направление считается по цвету
       того, кто ходит: белые идут вверх (меньше y), чёрные вниз. */
    let ходов = 0;
    let довели = false;
    for (let шаг = 0; шаг < 400 && !довели; шаг++) {
      const что = await страница.evaluate(() => {
        const плашка = document.getElementById('экран-превращения');
        if (плашка && плашка.classList.contains('экран--виден')) return 'превращение';

        const строка = (document.getElementById('строка-хода') || {}).textContent || '';
        const ходятБелые = /бел/i.test(строка);

        const можно = [...document.querySelectorAll('.поле--можно')];
        if (можно.length) {
          /* Идём вперёд: белым — вверх, чёрным — вниз. Бой предпочитаем
             всегда: он расчищает вертикаль перед пешкой. */
          const бой = можно.filter((п) => /бить|взят/i.test(п.className));
          const выбор = (бой.length ? бой : можно).sort((а, б) => {
            const яА = а.getBoundingClientRect().top;
            const яБ = б.getBoundingClientRect().top;
            return ходятБелые ? яА - яБ : яБ - яА;
          })[0];
          выбор.click();
          window.__тупики = new Set();   // походили — прежние тупики устарели
          return 'пошли';
        }

        /* Поднимаем свою САМУЮ ПРОДВИНУТУЮ пешку — она ближе всех к краю. */
        const свои = [...document.querySelectorAll('.фигура')].filter((ф) =>
          ф.classList.contains('фигура--белая') === ходятБелые);
        if (!свои.length) return 'нечего';
        const пешки = свои.filter((ф) => /♟|пешк/i.test((ф.textContent || '') + ' ' + ф.className));
        /* Самая продвинутая пешка бывает заперта: тогда подсветки нет,
           и стенд крутится, поднимая её снова и снова. Поэтому берём
           не первую, а первую из тех, что ещё не оказались тупиком
           в этом заходе, и время от времени — случайную. */
        const порядок = (пешки.length ? пешки : свои).slice().sort((а, б) => {
          const яА = а.getBoundingClientRect().top;
          const яБ = б.getBoundingClientRect().top;
          return ходятБелые ? яА - яБ : яБ - яА;
        });
        window.__тупики = window.__тупики || new Set();
        const примета = (ф) => (ф.textContent || '') + '@' + Math.round(ф.getBoundingClientRect().left) + ',' + Math.round(ф.getBoundingClientRect().top);
        const годные = порядок.filter((ф) => !window.__тупики.has(примета(ф)));
        const кого = (годные.length ? годные : порядок)[0];
        window.__последняя = примета(кого);
        кого.click();
        /* Если после нажатия ничего не подсветилось — эта фигура заперта. */
        if (!document.querySelectorAll('.поле--можно').length) window.__тупики.add(window.__последняя);
        return 'подняли';
      });
      if (что === 'превращение') { довели = true; break; }
      if (что === 'пошли') ходов++;
      await спать(что === 'нечего' ? 150 : 90);
    }

    console.log('  ходов сделано: ' + ходов + ', плашка превращения: ' + (довели ? 'появилась' : 'не появилась'));
    проверить(довели, 'пешку удалось довести до края и плашка превращения показалась');

    if (довели) {
      const плашка = await страница.evaluate(() => {
        const п = document.getElementById('экран-превращения');
        const кнопки = [...п.querySelectorAll('button')].filter((к) => к.offsetParent !== null).map((к) => {
          const м = к.getBoundingClientRect();
          return { что: (к.textContent || '').trim().slice(0, 16), ш: Math.round(м.width), в: Math.round(м.height) };
        });
        const м = п.getBoundingClientRect();
        return {
          кнопок: кнопки.length, кнопки: кнопки,
          вОкне: м.top >= -1 && м.bottom <= window.innerHeight + 1,
          мелких: кнопки.filter((к) => к.в < 44).length,
          текст: (п.textContent || '').replace(/\s+/g, ' ').trim().slice(0, 80)
        };
      });
      console.log('  на плашке: «' + плашка.текст + '»');
      console.log('  кнопки: ' + плашка.кнопки.map((к) => к.что + ' ' + к.ш + '×' + к.в).join(', '));
      проверить(плашка.кнопок >= 4, 'четыре выбора фигуры и больше: ' + плашка.кнопок);
      проверить(плашка.мелких === 0, 'все кнопки крупные, не ниже 44 точек: мелких ' + плашка.мелких);
      проверить(плашка.вОкне, 'плашка целиком в окне');
      await страница.screenshot({ path: ПАПКА + 'шахматы-превращение.png' });
      console.log('  снимок: ' + ПАПКА + 'шахматы-превращение.png');

      /* Нажимаем пальцем первый выбор — плашка обязана закрыться,
         а на доске обязана появиться новая фигура вместо пешки. */
      const доФигур = await страница.evaluate(() => document.querySelectorAll('.фигура').length);
      await страница.evaluate(() => {
        const п = document.getElementById('экран-превращения');
        const к = [...п.querySelectorAll('button')].filter((б) => б.offsetParent !== null)[0];
        if (к) к.click();
      });
      await спать(900);
      const после = await страница.evaluate(() => ({
        открыта: document.getElementById('экран-превращения').classList.contains('экран--виден'),
        фигур: document.querySelectorAll('.фигура').length,
        строка: (document.getElementById('строка-хода') || {}).textContent || ''
      }));
      console.log('  после выбора: плашка открыта ' + после.открыта + ', фигур ' + после.фигур +
        ' (было ' + доФигур + '), строка «' + после.строка.trim().slice(0, 40) + '»');
      проверить(!после.открыта, 'выбор фигуры пальцем закрывает плашку');
      проверить(после.фигур === доФигур, 'фигур на доске столько же — пешка сменилась, а не пропала');
    }
    проверить(красные.length === 0, 'консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));
    await окно.close();
  }

  /* ================================================================
     2. Рекорды: серия побед и ничья
     ================================================================ */
  console.log('\n=== Рекорды шахмат: серия и ничья ===');
  {
    const { окно, страница, красные } = await новая(браузер, 320, 568);

    const дверь = await страница.evaluate(() => typeof (window.ШахматыРекорды || {}).записатьПартию);
    проверить(дверь === 'function', 'дверь рекордов на месте (ШахматыРекорды.записатьПартию)');

    /* Пишем партии той же дверью, которой пользуется сама игра. Порядок
       нарочный: две победы, ничья, ещё победа — так видно и растёт ли
       серия, и что с ней делает ничья. */
    const подписи = await страница.evaluate(async () => {
      const шаги = [
        { исход: 'победа', уровень: 'сложный' },
        { исход: 'победа', уровень: 'сложный' },
        { исход: 'ничья', уровень: 'сложный' },
        { исход: 'победа', уровень: 'сложный' },
        { исход: 'поражение', уровень: 'сложный' },
        { исход: 'победа', уровень: 'лёгкий' }
      ];
      const итог = [];
      for (const шаг of шаги) итог.push(await window.ШахматыРекорды.записатьПартию(шаг));
      return итог;
    });
    подписи.forEach((п, н) => console.log('     ' + (н + 1) + '. ' + п));

    /* Главная тонкость: ничья не рвёт серию и не растит её. */
    const послеДвух = String(подписи[1] || '');
    const послеНичьей = String(подписи[2] || '');
    const послеТретьей = String(подписи[3] || '');
    const числоИз = (с) => { const м = /(\d+)/.exec(с || ''); return м ? Number(м[1]) : null; };
    console.log('  серия: после двух побед ' + числоИз(послеДвух) +
      ', после ничьей ' + числоИз(послеНичьей) + ', после третьей победы ' + числоИз(послеТретьей));
    проверить(!/прерв|обнул|сброш/i.test(послеНичьей),
      'ничья не названа обрывом серии: «' + послеНичьей + '»');
    проверить(числоИз(послеНичьей) === числоИз(послеДвух),
      'ничья серию не растит и не рвёт: было ' + числоИз(послеДвух) + ', стало ' + числоИз(послеНичьей));
    проверить(числоИз(послеТретьей) === (числоИз(послеДвух) || 0) + 1,
      'после ничьей победа продолжает ту же серию: ' + числоИз(послеТретьей));
    проверить(/прерв|обнул|сброш|0/i.test(String(подписи[4] || '')),
      'поражение серию обрывает: «' + подписи[4] + '»');

    /* Строка серии на плашке итога и таблица на узком экране. */
    await страница.evaluate(() => { if (window.ШахматыРекорды.показать) window.ШахматыРекорды.показать(); });
    await спать(700);
    const таблица = await страница.evaluate(() => {
      const т = document.getElementById('таблица-рекордов');
      const строки = [...т.querySelectorAll('.таблица__строка')];
      return {
        видна: document.getElementById('экран-рекордов').classList.contains('экран--виден'),
        подпись: (document.getElementById('лучший-рекорд') || {}).textContent || '',
        строк: строки.length,
        первые: строки.slice(0, 4).map((с) => (с.textContent || '').replace(/\s+/g, ' ').trim().slice(0, 46)),
        обрезано: строки.filter((с) => с.scrollWidth > с.clientWidth + 1).length,
        ширина: document.documentElement.scrollWidth, окно: window.innerWidth
      };
    });
    console.log('  «' + таблица.подпись.trim() + '»');
    таблица.первые.forEach((с) => console.log('     · ' + с));
    проверить(таблица.видна, 'экран рекордов открылся');
    проверить(таблица.строк >= 2, 'в таблице есть строки: ' + таблица.строк);
    проверить(таблица.обрезано === 0, 'на 320 ни одна строка не обрезана: обрезанных ' + таблица.обрезано);
    проверить(таблица.ширина <= таблица.окно + 1, 'страница не едет вбок: ' + таблица.ширина);
    await страница.screenshot({ path: ПАПКА + 'шахматы-рекорды-320.png', fullPage: true });
    console.log('  снимок: ' + ПАПКА + 'шахматы-рекорды-320.png');

    проверить(красные.length === 0, 'консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));
    await окно.close();
  }

  await браузер.close();
  console.log('\nИтог: провалов ' + провалов);
  process.exit(провалов ? 1 : 0);
})().catch((о) => { console.error('Стенд упал: ' + (о && о.stack || о)); process.exit(2); });
