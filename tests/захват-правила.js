// Подменённый случай: всегда одно число. Считает вызовы.
function случайВсегда(число) {
  const ф = () => { ф.вызовов++; return число; };
  ф.вызовов = 0;
  return ф;
}
// Подменённый случай: числа по очереди; кончились — ошибка (значит, вытянуто больше, чем ждали).
function случайОчередь(числа) {
  const ф = () => {
    if (ф.вызовов >= числа.length) throw new Error('очередь случая кончилась на ' + (ф.вызовов + 1) + '-м числе');
    return числа[ф.вызовов++];
  };
  ф.вызовов = 0;
  return ф;
}

// Партия для случаев раздела 16: владения и войска руками, подкрепление 0 у всех, черновики пустые.
function партияДляРазбора(П, владения, войска, карта) {
  const п = карта === 'остров'
    ? П.новаяПартия({ игроки: ['X', 'Y'], столицы: { X: 'J', Y: 'Q' }, порядок: ['X', 'Y'], областейНаСтарте: 2, карта: 'остров' }, () => 0)
    : партияМатерик(П);
  задатьВладения(п, владения, войска);
  п.игроки.forEach((к) => { п.подкрепление[к] = 0; });
  return п;
}

