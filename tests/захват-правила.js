function проверитьТекст(текст) {
  // Без DOM, своих часов и своего случая (0.1 плана).
  [['Math.random', /Math\.random/], ['Date', /\bDate\b/], ['document', /\bdocument\b/],
    ['setTimeout', /setTimeout/], ['setInterval', /setInterval/]].forEach(([слово, образец]) => {
    проверить(!образец.test(текст), 'в тексте файла нет «' + слово + '»');
  });
  // Все числа — одним объектом ЧИСЛА в одном месте.
  const начала = текст.split('const ЧИСЛА = {').length - 1;
  проверить(начала === 1, 'объект ЧИСЛА объявлен ровно один раз (нашлось ' + начала + ')');
  const начало = текст.indexOf('const ЧИСЛА = {');
  const конец = текст.indexOf('\n  };', начало);
  проверить(начало !== -1 && конец !== -1, 'блок ЧИСЛА найден');
  const вне = текст.slice(0, начало) + текст.slice(конец);
  const чужие = вне.match(/\b0\.[0-9]+/g) || [];
  проверить(чужие.length === 0, 'дробных чисел вне ЧИСЛА нет (нашлось: ' + чужие.join(', ') + ')');
  проверить(/module\.exports = ЗахватПравила/.test(текст) && /window\.ЗахватПравила = ЗахватПравила/.test(текст),
    'файл отдаёт и module.exports, и window.ЗахватПравила');
}

