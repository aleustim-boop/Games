// Итог по договору 15.2: одна строка победителя, остальные — проигравшие, ничьей нет;
// функция итог() даёт то же, что записано в партию.
function итогПоДоговору(П, партия, победитель, метка) {
  проверить(партия.завершена === true, метка + ': партия завершена');
  проверить(typeof партия.результат === 'string' && партия.результат === победитель,
    метка + ': результат — строка «' + победитель + '» (вышло ' + JSON.stringify(партия.результат) + ')');
  // Победителей может быть несколько (верхняя половина стола, А4д); результат — первый из них.
  const победители = партия.победители;
  проверить(Array.isArray(победители) && победители.indexOf(победитель) !== -1 &&
    new Set(победители).size === победители.length && !!партия.итог &&
    JSON.stringify(партия.итог.победители) === JSON.stringify(победители),
    метка + ': победители — список без повторов, в нём победитель, он же в итоге (вышло ' + JSON.stringify(победители) + ')');
  const прочие = партия.игроки.filter((к) => (победители || []).indexOf(к) === -1).sort().join(' ');
  проверить(Array.isArray(партия.проигравшие) && партия.проигравшие.slice().sort().join(' ') === прочие,
    метка + ': проигравшие — все, кроме победителей (вышло ' + JSON.stringify(партия.проигравшие) + ')');
  проверить(партия.ничья === false, метка + ': ничья = false');
  const и = П.итог(партия);
  проверить(и.завершена === true && и.результат === партия.результат && и.ничья === false &&
    JSON.stringify(и.проигравшие) === JSON.stringify(партия.проигравшие) &&
    JSON.stringify(и.итог) === JSON.stringify(партия.итог),
    метка + ': итог(партия) совпадает с записанным в партию');
  проверить(!!партия.итог && партия.итог.места.length === партия.игроки.length &&
    партия.итог.места.filter((м) => м.место === 1).length === 1 && партия.итог.места[0].кто === победитель,
    метка + ': в местах ровно одно первое — победитель');
}

function приказы(...список) {
  return { расстановка: {}, приказы: список.map(([из, в, сколько]) => ({ из, в, сколько })) };
}

// Разбор с общими проверками: исходная партия не тронута, итог переживает JSON.
function разобрать(П, партия, черновики, случай, метка) {
  const до = JSON.stringify(партия);
  const р = П.разобратьРаунд(партия, черновики, случай);
  проверить(JSON.stringify(партия) === до, метка + ': исходная партия не изменилась');
  let одинаково = true;
  try {
    assert.deepStrictEqual(JSON.parse(JSON.stringify(р)), р);
  } catch (ошибка) {
    одинаково = false;
  }
  проверить(одинаково, метка + ': партия и события после разбора переживают JSON');
  return р;
}

function событияВида(р, вид) {
  return р.события.filter((с) => с.вид === вид);
}

// Сверка области: хозяин и войска после разбора.
function областьКак(р, номерОбласти, хозяин, войск, метка) {
  const х = р.партия.хозяева[номерОбласти];
  const в = р.партия.войска[номерОбласти];
  проверить(х === хозяин && в === войск,
    метка + ': область ' + номерОбласти + ' — ' + х + ', ' + в + ' войск; ждали ' + хозяин + ', ' + войск);
}

