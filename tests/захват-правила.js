// Дорога сервера: require. Текст копии компилируется с путём настоящего файла.
function загрузитьКакМодуль(текст) {
  const м = new Module(ФАЙЛ_ПРАВИЛ, module);
  м.filename = ФАЙЛ_ПРАВИЛ;
  м.paths = Module._nodeModulePaths(path.dirname(ФАЙЛ_ПРАВИЛ));
  м._compile(текст, ФАЙЛ_ПРАВИЛ);
  return м.exports;
}

// Дорога браузера: песочница с window, карты подключены раньше правил.
// В ней же вызывается раздача — с пределом времени.
function собратьПесочницу(текст) {
  const окно = {};
  окно.window = окно;
  const песочница = vm.createContext(окно);
  vm.runInContext(fs.readFileSync(ФАЙЛ_КАРТ, 'utf8'), песочница, { filename: ФАЙЛ_КАРТ });
  vm.runInContext(текст, песочница, { filename: ФАЙЛ_ПРАВИЛ });
  // Случай для жребия: детерминированный генератор по зерну (Mulberry32).
  vm.runInContext(
    'function генератор(зерно) { let с = зерно >>> 0; return function () {' +
    ' с = (с + 0x6D2B79F5) >>> 0; let т = с; т = Math.imul(т ^ (т >>> 15), т | 1);' +
    ' т ^= т + Math.imul(т ^ (т >>> 7), т | 61); return ((т ^ (т >>> 14)) >>> 0) / 4294967296; }; }',
    песочница);
  return песочница;
}

// Новая партия в песочнице за ≤ 1 с. Отдаёт { партия, мс } или { ошибка }.
function раздатьСПределом(песочница, настройки, зерно) {
  const вызов = 'JSON.stringify(window.ЗахватПравила.новаяПартия(' + JSON.stringify(настройки) +
    ', генератор(' + (зерно || 1) + ')))';
  const начало = process.hrtime.bigint();
  try {
    const текст = vm.runInContext(вызов, песочница, { timeout: ПРЕДЕЛ_РАЗДАЧИ_МС });
    const мс = Number(process.hrtime.bigint() - начало) / 1e6;
    return { партия: JSON.parse(текст), мс: мс };
  } catch (ошибка) {
    return { ошибка: ошибка.message };
  }
}

