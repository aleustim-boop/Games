function номер(буква) {
  return 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcd'.indexOf(буква) + 1;
}
function буква(н) {
  return 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcd'[н - 1];
}

// Области каждого места буквами по порядку: {ключ: 'A B C E'}, ничьи — под ключом «ничьи».
function владенияБуквами(партия) {
  const итог = {};
  партия.игроки.forEach((к) => { итог[к] = []; });
  итог.ничьи = [];
  for (let н = 1; н < партия.хозяева.length; н++) {
    const х = партия.хозяева[н];
    (х === null ? итог.ничьи : итог[х]).push(буква(н));
  }
  Object.keys(итог).forEach((к) => { итог[к] = итог[к].join(' '); });
  return итог;
}

// Партия на Материке без жребия; затем владения задаются руками: {ключ: [номера]}, прочие — ничьи.
function партияМатерик(П) {
  return П.новаяПартия({
    игроки: ['X', 'Y', 'Z', 'W'],
    столицы: { X: 'B', Y: 'G', Z: 'O', W: 'Q' },
    порядок: ['X', 'Y', 'Z', 'W'],
    областейНаСтарте: 4,
    карта: 'материк'
  }, () => 0);
}
function задатьВладения(партия, владения, войска) {
  for (let н = 1; н < партия.хозяева.length; н++) партия.хозяева[н] = null;
  Object.keys(владения).forEach((к) => владения[к].forEach((н) => { партия.хозяева[н] = к; }));
  Object.keys(войска || {}).forEach((н) => { партия.войска[Number(н)] = войска[н]; });
  return партия;
}

