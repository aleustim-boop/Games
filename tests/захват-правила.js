// Таблица 2.2: карта, раунды, области у каждого, ничьи — на многих жребиях; целого края ни у кого.
function проверитьСоставы(П, мир) {
  const ТАБЛИЦА_2_2 = {
    2: { карта: 'остров', раундов: 12, у: 6, ничьих: 6 },
    3: { карта: 'остров', раундов: 12, у: 5, ничьих: 3 },
    4: { карта: 'материк', раундов: 15, у: 6, ничьих: 6 },
    5: { карта: 'материк', раундов: 15, у: 5, ничьих: 5 },
    6: { карта: 'материк', раундов: 15, у: 4, ничьих: 6 }
  };
  let раздач = 0;
  Object.keys(ТАБЛИЦА_2_2).forEach((мест) => {
    const ждём = ТАБЛИЦА_2_2[мест];
    const игроки = Array.from({ length: Number(мест) }, (_, и) => 'м' + (и + 1));
    const исходы = new Set();
    for (let зерно = 1; зерно <= 20; зерно++) {
      const р = раздатьСПределом(мир.песочница, { игроки: игроки }, зерно);
      if (р.ошибка) {
        проверить(false, '2.2: ' + мест + ' мест, зерно ' + зерно + ' — ' + р.ошибка);
        continue;
      }
      раздач++;
      const п = р.партия;
      const в = владенияБуквами(п);
      исходы.add(JSON.stringify(в));
      проверить(п.карта === ждём.карта && п.всегоРаундов === ждём.раундов,
        '2.2: ' + мест + ' мест — карта ' + п.карта + ', раундов ' + п.всегоРаундов);
      игроки.forEach((к) => {
        const областей = в[к].split(' ').filter(Boolean).length;
        проверить(областей === ждём.у, '2.2: ' + мест + ' мест, зерно ' + зерно + ': у ' + к + ' ' + областей + ' областей, ждали ' + ждём.у);
        проверить(П.подкрепление(п, к).края.length === 0, '2.2: ' + мест + ' мест, зерно ' + зерно + ': у ' + к + ' целый край на старте');
      });
      проверить(в.ничьи.split(' ').filter(Boolean).length === ждём.ничьих, '2.2: ' + мест + ' мест — ничьих не ' + ждём.ничьих);
      проверить(п.столицы.length === Number(мест) && п.столицы.every((с) => п.хозяева[с.область] === с.хозяинНаСтарте && п.войска[с.область] === 4),
        '2.2: ' + мест + ' мест — у каждого своя столица с 4 войсками');
      проверить(игроки.every((к) => п.подкрепление[к] === П.подкрепление(п, к).всего),
        '2.2: подкрепление первого раунда посчитано всем');
      проверить(игроки.every((к) => JSON.stringify(п.черновики[к]) === '{"расстановка":{},"приказы":[]}'),
        '2.2: черновики первого раунда пустые');
    }
    проверить(исходы.size > 1, '2.2: ' + мест + ' мест — жребий меняет раздачу (разных исходов ' + исходы.size + ')');
  });
  проверить(раздач === 100, '2.2: прошло раздач ' + раздач + ', ждали 100');

  // Один и тот же случай — одна и та же партия (сервер и проверки повторяемы).
  const а = раздатьСПределом(мир.песочница, { игроки: ['а', 'б', 'в', 'г'] }, 7);
  const б = раздатьСПределом(мир.песочница, { игроки: ['а', 'б', 'в', 'г'] }, 7);
  проверить(!а.ошибка && JSON.stringify(а.партия) === JSON.stringify(б.партия), '2.5: тот же случай — та же раздача');

  // Первая партия новичка: Остров, A, J, Q, человек в A; у него есть ничья соседняя (2.5 п. 7).
  let новичков = 0;
  for (let зерно = 1; зерно <= 20; зерно++) {
    const р = раздатьСПределом(мир.песочница, { игроки: ['бот1', 'я', 'бот2'], новичок: 'я', люди: ['я'] }, зерно);
    if (р.ошибка) {
      проверить(false, '2.5 п. 7: новичок, зерно ' + зерно + ' — ' + р.ошибка);
      continue;
    }
    новичков++;
    const п = р.партия;
    const мояСтолица = п.столицы.find((с) => с.хозяинНаСтарте === 'я');
    проверить(п.карта === 'остров' && мояСтолица && мояСтолица.область === 1, '2.5 п. 7: новичок на Острове в гнезде A');
    проверить(п.столицы.map((с) => буква(с.область)).sort().join('') === 'AJQ', '2.5 п. 7: набор столиц A, J, Q');
    проверить(ничьихРядом(п, 'я') > 0, '2.5 п. 7: у новичка есть ничья соседняя область (зерно ' + зерно + ')');
  }
  проверить(новичков === 20, '2.5 п. 7: прошло раздач новичка ' + новичков + ', ждали 20');
}

// Сколько ничьих областей касаются хоть одной области ключа.
function ничьихРядом(партия, ключ) {
  const соседи = require(ФАЙЛ_КАРТ).соседство(require(ФАЙЛ_КАРТ).КАРТЫ[партия.карта]);
  const рядом = new Set();
  партия.хозяева.forEach((х, н) => {
    if (н === 0 || х !== ключ) return;
    (соседи[н] || []).forEach((с) => { if (партия.хозяева[с] === null) рядом.add(с); });
  });
  return рядом.size;
}

// JSON-круг: партия после stringify/parse — та же, и функции дают на ней то же.
function проверитьJSON(П) {
  const п = П.новаяПартия({ игроки: ['а', 'б', 'в', 'г', 'д'], люди: ['а'], сейчас: 1000 }, (() => {
    let с = 0;
    return () => { с = (с * 9301 + 49297) % 233280; return с / 233280; };
  })());
  const копия = JSON.parse(JSON.stringify(п));
  let одинаково = true;
  try {
    assert.deepStrictEqual(копия, п);
  } catch (ошибка) {
    одинаково = false;
  }
  проверить(одинаково, 'JSON-круг: партия после stringify/parse та же самая (нет undefined, функций, бесконечностей)');
  проверить(п.началась === 1000, 'время начала приходит доводом (началась = 1000)');
  проверить(п.игроки.every((к) => JSON.stringify(П.подкрепление(п, к)) === JSON.stringify(П.подкрепление(копия, к))),
    'JSON-круг: подкрепление на копии то же');
  const своя = копия.хозяева.findIndex((х) => х === 'а');
  const черновик = { расстановка: { [своя]: копия.подкрепление.а }, приказы: [] };
  проверить(П.проверитьЧерновик(копия, 'а', JSON.parse(JSON.stringify(черновик))).принято === true,
    'JSON-круг: черновик на копии партии принят');
}

