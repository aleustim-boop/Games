function сломать() {
  const исходник = fs.readFileSync(ФАЙЛ_ПРАВИЛ, 'utf8');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-правила-'));
  let подвело = 0;
  ПОРЧИ.forEach((порча, и) => {
    const частей = исходник.split(порча.найти).length - 1;
    if (частей !== 1) {
      console.log('  ПЛОХО— порча «' + порча.имя + '»: образец найден ' + частей + ' раз, нужен ровно 1 — проверка не может краснеть');
      подвело++;
      return;
    }
    const копия = path.join(папка, 'копия-' + (и + 1) + '.js');
    fs.writeFileSync(копия, исходник.replace(порча.найти, порча.заменить), 'utf8');
    const итог = spawnSync(process.execPath, [__filename, '--файл', копия], { encoding: 'utf8', timeout: 120000 });
    const строка = ((итог.stdout || '').match(/Итого проверок: \d+, провалов: \d+/) || ['(итога нет)'])[0];
    const нужныйСлучай = !порча.краснеет || (итог.stdout || '').indexOf('ПЛОХО— случай ' + порча.краснеет + ':') !== -1;
    const покраснела = итог.status === 1 && /провалов: [1-9]/.test(строка) && нужныйСлучай;
    console.log((покраснела ? '  ок   — ' : '  ПЛОХО— ') + порча.имя + ': ' + строка + ', код ' + итог.status +
      (порча.краснеет ? (нужныйСлучай ? ', покраснел случай ' : ', НЕ покраснел случай ') + порча.краснеет : ''));
    if (!покраснела) подвело++;
  });
  fs.rmSync(папка, { recursive: true, force: true });
  console.log('\nПорч не замеченных проверкой: ' + подвело + ' из ' + ПОРЧИ.length);
  process.exit(подвело ? 1 : 0);
}

