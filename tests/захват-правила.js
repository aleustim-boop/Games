function прогнать(файл) {
  const текст = fs.readFileSync(файл, 'utf8');
  let П;
  let песочница;
  try {
    П = загрузитьКакМодуль(текст);
    песочница = собратьПесочницу(текст);
  } catch (ошибка) {
    проверить(false, 'файл загружается без ошибок (' + ошибка.message + ')');
    return;
  }
  проверить(!!песочница.ЗахватПравила, 'в браузере файл отдаёт window.ЗахватПравила');
  const мир = { текст: текст, песочница: песочница };

  проверитьТекст(текст);
  проверитьВыход(П);
  проверить(СЛУЧАИ.length >= 8, 'случаев в списке ' + СЛУЧАИ.length + ' (ноль найденного — провал)');
  СЛУЧАИ.forEach((с) => {
    const было = провалов;
    try {
      с.проверка(П, мир);
    } catch (ошибка) {
      проверить(false, 'случай ' + с.номер + ' упал: ' + ошибка.message);
    }
    console.log((провалов === было ? '  ок   — ' : '  ПЛОХО— ') + 'случай ' + с.номер + ': ' + с.имя);
  });
  const было = провалов;
  try {
    проверитьСоставы(П, мир);
    проверитьJSON(П);
  } catch (ошибка) {
    проверить(false, 'общие проверки упали: ' + ошибка.message);
  }
  console.log((провалов === было ? '  ок   — ' : '  ПЛОХО— ') + 'таблица 2.2, новичок, повторяемость, JSON-круг');
}

