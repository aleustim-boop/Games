/* =====================================================================
   ЦВЕТ ОКНА TELEGRAM НА ВИТРИНЕ: шапка, фон и нижняя полоса.

   Витрина тёмная (#101416), остальные экраны — зелёное сукно. В Telegram
   шапка окна и нижняя полоса должны перекраситься под витрину, а уходя
   с неё — вернуться обратно. Иначе над тёмной витриной висит зелёная
   шапка, а над сукном — чёрная.

   Как устроена. Поддельный браузер (tests/поддельный-браузер.js) плюс
   поддельный Telegram, который записывает каждую просьбу перекрасить.
   Проверяем, что просили и в каком порядке, и что старые версии Telegram,
   у которых этих просьб нет, не падают.

   Написал разработчик, пока делал витрину; тестировщик перенёс в tests/:
   пути теперь считаются от папки проверок. Номер style.css больше не
   сравнивается с числом, вписанным внутрь проверки, — он сравнивается с
   номером из коммита до витрины, прочитанным из самого index.html.

   Запуск:
     node tests/цвет-окна-телеграма.js          — нынешние файлы, должно быть 0 провалов
     node tests/цвет-окна-телеграма.js было     — файлы из коммита до новой витрины;
                                                  обязан провалиться
     node tests/цвет-окна-телеграма.js было abc123 — то же, из указанного коммита
   ===================================================================== */
'use strict';

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const подделка = require(path.join(__dirname, 'поддельный-браузер.js'));

/* Последний коммит со старой витриной (10 сентября, 19:25). Не «HEAD»:
   после коммита штаба HEAD станет новой витриной, и режим «было» тихо
   позеленел бы. */
const КОММИТ_ДО_ВИТРИНЫ = '8102389';

const поБыло = process.argv[2] === 'было';
const коммитБыло = process.argv[3] || КОММИТ_ДО_ВИТРИНЫ;

function изКоммита(коммит, имя) {
  return execFileSync('git', ['show', коммит + ':' + имя], { cwd: КОРЕНЬ, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
}

function файл(имя) {
  if (!поБыло) return fs.readFileSync(path.join(КОРЕНЬ, имя), 'utf8');
  return изКоммита(коммитБыло, имя);
}

function собратьРазметку(html, документ) {
  const чистый = html.replace(/<!--[\s\S]*?-->/g, '').replace(/<script[\s\S]*?<\/script>/g, '');
  const тело = /<body[^>]*>([\s\S]*)<\/body>/.exec(чистый)[1];
  const образец = /<(\/?)([a-zA-Z][\w-]*)([^>]*?)(\/?)>|([^<]+)/g;
  const ПУСТЫЕ = new Set(['input', 'br', 'img', 'meta', 'link', 'hr']);
  const стек = [документ.body];
  let м;
  while ((м = образец.exec(тело))) {
    if (м[5] !== undefined) { if (м[5].trim()) стек[стек.length - 1].appendChild(документ.createTextNode(м[5])); continue; }
    const тег = м[2].toLowerCase();
    if (м[1] === '/') { for (let i = стек.length - 1; i > 0; i--) if (стек[i].tagName === тег.toUpperCase()) { стек.length = i; break; } continue; }
    const узел = документ.createElement(тег);
    const атр = /([^\s=]+)(?:\s*=\s*"([^"]*)")?/g;
    let а;
    while ((а = атр.exec(м[3]))) { узел.setAttribute(а[1], а[2] === undefined ? '' : а[2]); if (а[1] === 'disabled') узел.disabled = true; }
    стек[стек.length - 1].appendChild(узел);
    if (м[4] !== '/' && !ПУСТЫЕ.has(тег)) стек.push(узел);
  }
}

/** Номер style.css в разметке (?v=N) — или NaN, если его нет. */
function номерСтиля(html) {
  const м = /style\.css\?v=(\d+)/.exec(html);
  return м ? Number(м[1]) : NaN;
}

/** Сравнение версий, как у настоящего Telegram: «7.10» выше «7.9». */
function неНиже(есть, нужна) {
  const а = String(есть).split('.').map(Number);
  const б = String(нужна).split('.').map(Number);
  for (let i = 0; i < Math.max(а.length, б.length); i++) {
    const х = а[i] || 0, у = б[i] || 0;
    if (х !== у) return х > у;
  }
  return true;
}

/** Поддельный Telegram версии «версия»; «методы: false» — без методов цвета вовсе. */
function сделатьТелеграм(версия, методы) {
  const журнал = [];
  const события = {};
  const т = {
    version: версия, initData: 'подпись', platform: 'android',
    isVersionAtLeast: function (н) { return неНиже(версия, н); },
    onEvent: function (имя, дело) { (события[имя] = события[имя] || []).push(дело); },
    журнал: журнал, события: события
  };
  if (методы !== false) {
    т.setHeaderColor = function (ц) { журнал.push('шапка ' + ц); };
    т.setBackgroundColor = function (ц) { журнал.push('фон ' + ц); };
    т.setBottomBarColor = function (ц) { журнал.push('полоса ' + ц); };
  }
  return т;
}

/**
 * Поднять страницу. «фонСтола» — чем оформление красит #экран-игры; не
 * задан — стол как страница (так было до 11 сентября, разделам 1–3 он
 * не нужен: там с витрины уходят в меню, а не за стол).
 */
function поднять(телеграм, фонСтола) {
  const документ = подделка.сделатьДокумент();
  собратьРазметку(файл('index.html'), документ);
  const настройки = { документ: документ, имяФайла: 'js/telegram.js' };
  if (телеграм) настройки.telegram = телеграм;
  const стр = подделка.поднять(файл('js/telegram.js'), настройки);
  // Оформление: витрина тёмная (#101416), страница — зелёное сукно (#14532d).
  стр.окно.getComputedStyle = function (узел) {
    const ид = узел && узел.id;
    const фон = ид === 'экран-витрины' ? 'rgb(16, 20, 22)'
      : (ид === 'экран-игры' && фонСтола ? фонСтола : 'rgb(20, 83, 45)');
    return { backgroundColor: фон, getPropertyValue: function () { return ''; } };
  };
  стр.спросить(файл('js/game.js'));
  return стр;
}

let провалов = 0;
function проверить(да, что) { if (!да) провалов += 1; console.log((да ? '  ок   ' : '  ПРОВАЛ ') + что); }
function последнее(журнал, что) { const с = журнал.filter(function (з) { return з.indexOf(что + ' ') === 0; }); return с.length ? с[с.length - 1].slice(что.length + 1) : null; }
function сменаТемы(т) { (т.события.themeChanged || []).forEach(function (д) { д(); }); }
function загрузка(стр) {
  // Как в браузере на «load»: сперва js/telegram.js подсказал цвет страницы, потом витрина.
  стр.спросить('typeof освежитьЦветОкна === "function" ? освежитьЦветОкна(видимыйЭкран()) : null');
}

/** Раздел проверки: обрыв с ошибкой — тоже провал, но прогон идёт дальше. */
function раздел(имя, дело) {
  console.log(имя);
  try { дело(); } catch (беда) {
    провалов += 1;
    console.log('  ПРОВАЛ раздел оборвался: ' + (беда && беда.message ? беда.message : String(беда)));
  }
}

