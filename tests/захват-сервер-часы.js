'use strict';
/* =====================================================================
   ПРОВЕРКА «Захвата», этап ДП2: часы «До победы» на сервере (server/игры/захват.js).
   Сервер считает 10 минут по СВОИМ часам от начала партии: сон и уход игроков их не
   останавливают. В вид игрока уходит «мсДоКонцаПартии» (у обычного стола и у оконченной — null).

   Что требуется:
     - в начале — 600000, через 4 минуты — 360000, после 10:01 — 0 (не минус);
     - вид не пишет потраченоМс в партию;
     - разбор после 10:01 кончает партию, потраченоМс записан до разбора;
     - окончена — поле null; обычный стол — null; на 2:00 партия продолжается.

   Запуск:
     node tests/захват-сервер-часы.js                  — проверка
     node tests/захват-сервер-часы.js --файл путь.js   — сервер игры из другого файла (копия)
     node tests/захват-сервер-часы.js --сломать        — ломающие запуски на копиях во временной папке
   Выход: 0 — зелено; 1 — есть провалы; 2 — порча не покраснела; 3 — порче не нашлось места.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const КОРЕНЬ = path.resolve(__dirname, '..');
const ФАЙЛ_ИГРЫ = path.join(КОРЕНЬ, 'server', 'игры', 'захват.js');
const аргументы = process.argv.slice(2);
const номерФайла = аргументы.indexOf('--файл');

const ПОРЧИ = [
  { имя: 'потраченоМс не пишется перед разбором', найти: 'if (партия.доПобеды) партия.потраченоМс = сейчас() - началоПартии(партия);', на: '' },
  { имя: 'у обычного стола тоже есть часы', найти: 'if (!партия.доПобеды || партия.завершена) return null;', на: 'if (партия.завершена) return null;' },
  { имя: 'часы сервера стоят (потрачено всегда 0)', найти: 'потраченоМс: сейчас() - началоПартии(партия) };', на: 'потраченоМс: 0 };' },
  { имя: 'у оконченной партии часы остались', найти: 'if (!партия.доПобеды || партия.завершена) return null;', на: 'if (!партия.доПобеды) return null;' }
];

function сломать() {
  const исходник = fs.readFileSync(ФАЙЛ_ИГРЫ, 'utf8');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-сервер-часы-'));
  let худшее = 0;
  ПОРЧИ.forEach((п, н) => {
    const мест = исходник.split(п.найти).length - 1;
    if (мест !== 1) { console.log('  ПЛОХО — порча «' + п.имя + '»: образец найден ' + мест + ' раз, нужен ровно 1'); худшее = Math.max(худшее, 3); return; }
    // В копии относительные подключения заменяем абсолютными.
    const копияТекст = исходник.replace(п.найти, () => п.на)
      .split("require('../../js/").join("require('" + path.join(КОРЕНЬ, 'js').split(path.sep).join('/') + '/')
      .split("require('../партия-по-сети')").join("require('" + path.join(КОРЕНЬ, 'server', 'партия-по-сети').split(path.sep).join('/') + "')");
    const копия = path.join(папка, 'захват-' + н + '.js');
    fs.writeFileSync(копия, копияТекст);
    const итог = spawnSync(process.execPath, [__filename, '--файл', копия], { encoding: 'utf8' });
    const красное = итог.status === 1;
    console.log((красное ? '  ок    — покраснело: ' : '  ПЛОХО — НЕ ПОКРАСНЕЛО: ') + п.имя + ' (код ' + итог.status + ')' + (красное ? '' : '\n' + (итог.stdout || '') + (итог.stderr || '').slice(0, 300)));
    if (!красное) худшее = Math.max(худшее, 2);
  });
  console.log('Копии лежат в ' + папка + ' (проект не тронут)');
  process.exit(худшее);
}
if (аргументы.includes('--сломать')) сломать();

/* ---------- сама проверка ---------- */
const И = require(номерФайла >= 0 ? path.resolve(аргументы[номерФайла + 1]) : ФАЙЛ_ИГРЫ);
let плохо = 0;
let всего = 0;
function ок(у, т) { всего++; if (!у) { плохо++; console.log('ПРОВАЛ: ' + т); } }
let время = 1000000;
И.сейчас = () => время;
function стол(раундов) {
  return И.раздать(null, { игроки: ['a', 'b'], люди: ['a'], хозяин: 'a', раундовЗахвата: раундов });
}
const видДо = (п) => И.видДляИгрока(п, 'a', { места: ['a', 'b'], игроки: ['a', 'b'] }).захват;

const п = стол('победа');
ок(п.доПобеды === true, 'стол «До победы» создан (ноль — провал)');
ок(видДо(п).мсДоКонцаПартии === 600000, 'в начале 10:00 в запасе (' + видДо(п).мсДоКонцаПартии + ')');
время += 240000;
ок(видДо(п).мсДоКонцаПартии === 360000, 'через 4 минуты осталось 6:00 (' + видДо(п).мсДоКонцаПартии + ')');
ок(п.потраченоМс === 0, 'вид не пишет потраченоМс в партию');
время += 361000;
ок(видДо(п).мсДоКонцаПартии === 0, 'после 10:01 — 0, не минус (' + видДо(п).мсДоКонцаПартии + ')');
// Раунд, начатый до срока, доигрывается; после разбора партия кончается «по времени».
И.разобратьРаунд(п);
ок(п.завершена === true, 'после раунда на 10:01 партия окончена (завершена=' + п.завершена + ')');
ок(п.потраченоМс >= 600000, 'потраченоМс записан перед разбором (' + п.потраченоМс + ')');
ок(видДо(п).мсДоКонцаПартии === null, 'окончена — поле null (' + видДо(п).мсДоКонцаПартии + ')');
const о = стол(10);
ок(видДо(о).мсДоКонцаПартии === null, 'обычный стол — null (' + видДо(о).мсДоКонцаПартии + ')');
время = 5000000;
const р = стол('победа');
время += 120000;
И.разобратьРаунд(р);
ок(!р.завершена, 'на 2:00 партия продолжается');

console.log('Итого проверок: ' + всего + ', провалов: ' + плохо);
process.exit(плохо ? 1 : 0);
