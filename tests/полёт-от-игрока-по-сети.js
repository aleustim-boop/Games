'use strict';

/* =====================================================================
   НАПАРНИК-НАБЛЮДАТЕЛЬ: садится за стол компанией по коду и играет сам,
   а заодно печатает в консоль КАЖДОЕ событие сервера человеческими словами —
   ровно то, что легло бы в строку подсказки у живого игрока.

   Зачем это отдельным файлом. Проверка «карта соперника летит от ЕГО
   плашки» меряет два числа с разных концов: браузер (через зонд —
   tests/зонд-полёта-карт.js) видит, ИЗ КАКОГО УЗЛА улетела карта, а этот
   файл — НЕЗАВИСИМО, через настоящий ответ сервера (поле «событие»,
   его составляет server/партия-по-сети.js) — говорит, КТО ЭТУ КАРТУ
   на самом деле положил. Сверять браузерную угадку саму с собой нельзя:
   если взять «кто ходил» из той же Map, что и проверяем, находка гарантированно
   будет зелёной, даже если Map врёт.

   Отличие от tests/напарник-для-браузера.js — этот умеет ПЕРЕВОДИТЬ ход
   (действие «перевести»), то есть предпочитает перевод отбою всякий раз,
   когда в переводной партии в руке есть карта того же достоинства, что
   и любая карта на столе. Без этого случай «перевод» было бы нечем
   проверить: обычные напарники его не делают вовсе.

   Как запускать (сервер комнат уже поднят):
       node tests/полёт-от-игрока-по-сети.js 8796 войти AB12 имя Аня
       node tests/полёт-от-игрока-по-сети.js 8796 создать имя Аня мест 4 переводной

   Каждая строка о событии печатается в стандартный вывод в двух видах:
     человеческим текстом (для глаз) и следом — одной строкой JSON,
     помеченной префиксом «СОБЫТИЕ_JSON », чтобы её было легко выцепить
     из журнала одним grep, не трогая остальной болтливый вывод.
   ===================================================================== */

const http = require('http');

const ПОРТ = Number(process.argv[2]) || 8796;
const ЧТО_ДЕЛАТЬ = (process.argv[3] || 'войти').toLowerCase();
const КОД_КОМНАТЫ = (process.argv[4] || '').toUpperCase();
const ХОЗЯИН = '127.0.0.1';

function довод(имяДовода, поУмолчанию) {
  const где = process.argv.indexOf(имяДовода);
  if (где === -1) return поУмолчанию;
  return process.argv[где + 1];
}

const МОЁ_ИМЯ = довод('имя', 'Напарник') || 'Напарник';
const МЕСТ = Number(довод('мест', '0')) || 0;
const ХОЧУ_ПЕРЕВОДНОЙ = process.argv.indexOf('переводной') !== -1;
/* Необязательная задержка перед КАЖДЫМ ходом, миллисекунды: пауза 1500.
   Нужна тестировщику, чтобы напарник ходил не мгновенно, а как живой
   человек — без довода поведение прежнее (ходит сразу же). */
const ПАУЗА_ПЕРЕД_ХОДОМ = Number(довод('пауза', '0')) || 0;

const ЖДЁМ_ДОЛГО = 40000;
const ЖДЁМ_КОРОТКО = 15000;

function спросить(путь, тело, сколькоЖдать) {
  return new Promise((готово, беда) => {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, (ответ) => {
      let текст = '';
      ответ.setEncoding('utf8');
      ответ.on('data', (к) => { текст += к; });
      ответ.on('end', () => {
        let р = null;
        try { р = JSON.parse(текст); } catch (сбой) { р = { сырое: текст }; }
        готово({ код: ответ.statusCode, тело: р });
      });
    });
    запрос.setTimeout(сколькоЖдать || ЖДЁМ_КОРОТКО,
      () => запрос.destroy(new Error('сервер молчит дольше положенного')));
    запрос.on('error', беда);
    запрос.end(данные);
  });
}

const пауза = (мс) => new Promise((r) => setTimeout(r, мс));

function бьёт(чем, что, козырь) {
  if (чем.масть === что.масть) return чем.вес > что.вес;
  return чем.масть === козырь && что.масть !== козырь;
}

function мелкая(рука, номера, козырь) {
  const некозырные = номера.filter((i) => рука[i].масть !== козырь);
  const из = некозырные.length ? некозырные : номера;
  return из.reduce((лучший, i) => (рука[i].вес < рука[лучший].вес ? i : лучший), из[0]);
}

/** Достоинства всех карт, уже лежащих на столе (и в атаке, и в защите). */
function достоинстваНаСтоле(стол) {
  const набор = new Set();
  stolForEach(стол, (к) => набор.add(к.имя));
  return набор;
}
function stolForEach(стол, колбек) {
  стол.forEach((п) => { if (п.атака) колбек(п.атака); if (п.защита) колбек(п.защита); });
}

/**
 * Список намерений в порядке предпочтения — а не одно решение, как у обычного
 * напарника. Причина: перевод разрешён не всегда (например, в подходе уже
 * есть отбитая пара — «условие 2» в правилах игры), сервер такую попытку
 * отклонит, и напарнику всё равно нужно нормально отбиться следом, а не
 * сразу сдаваться словом «Беру». Поэтому здесь — очередь попыток: перевод
 * (если в руке есть карта того же достоинства, что лежит на столе), потом
 * отбой самой мелкой годной картой, и только потом «Беру».
 *
 * Ради самой этой проверки перевод стоит ПЕРВЫМ в очереди, а не вторым:
 * обычный напарник (tests/напарник-для-браузера.js) перевод не делает
 * вовсе, и без этой очереди случай «перевод» было бы нечем проверить.
 */
function попыткиЗащиты(вид) {
  const рука = вид.мояРука || [];
  const стол = вид.стол || [];
  const козырь = вид.козырь;
  const попытки = [];

  if (вид.переводной) {
    const достоинства = достоинстваНаСтоле(стол);
    рука.forEach((к, i) => { if (достоинства.has(к.имя)) попытки.push({ действие: 'перевести', карта: i }); });
  }

  const номерПары = стол.findIndex((п) => !п.защита);
  if (номерПары >= 0) {
    const атака = стол[номерПары].атака;
    const годные = [];
    рука.forEach((к, i) => { if (атака && бьёт(к, атака, козырь)) годные.push(i); });
    if (годные.length) {
      // Сортируем от мелкой к крупной — пробуем по очереди, если сервер
      // почему-то откажет самой мелкой (не должен, но проверка не должна
      // вставать колом из-за наших же догадок).
      годные.sort((а, б) => рука[а].вес - рука[б].вес);
      годные.forEach((i) => попытки.push({ действие: 'отбить', пара: номерПары, карта: i }));
    }
  }

  popПробуемЗапасное(попытки);
  return попытки;
}

/** Что делать при своём ходе (атака, подкидывание) — сюда перевод не входит:
 *  переводит только защищающийся, а не тот, чья очередь атаковать. */
function решить(вид) {
  const рука = вид.мояРука || [];
  const стол = вид.стол || [];
  const козырь = вид.козырь;

  const яОтбиваюсь = вид.яОтбиваюсь !== undefined
    ? вид.яОтбиваюсь
    : Boolean(вид.яХожу && !вид.яАтакую);

  if (вид.яХожу && !яОтбиваюсь) {
    if (!рука.length) return стол.length ? { действие: 'бито' } : null;
    if (!стол.length) {
      const все = рука.map((к, i) => i);
      return { действие: 'ходить', карта: мелкая(рука, все, козырь) };
    }
    const достоинства = достоинстваНаСтоле(стол);
    const годные = [];
    рука.forEach((к, i) => { if (достоинства.has(к.имя)) годные.push(i); });
    if (годные.length) return { действие: 'ходить', карта: мелкая(рука, годные, козырь) };
    return { действие: 'бито' };
  }
  return null;
}

/* ---------------------------------------------------------------------
   Рассказ о событии — из вид.событие, теми же словами, что видит игрок.
   Разбираем текст ровно так, как его собирает server/партия-по-сети.js
   (см. РАССКАЗ_С_КАРТАМИ и ктоЭтоБыл): «Имя глагол {карта}» для чужого
   хода, «Вы глагол {карта}» для своего. Берём последний символ карты
   в строке — при отбое там ДВЕ карты («покрыл» и «чем»), и класть
   на стол только что могли именно вторую (ту, которой покрыли).
   --------------------------------------------------------------------- */

const ГЛАГОЛ_К_ДЕЙСТВИЮ = [
  { глагол: 'ходит', действие: 'ход' },
  { глагол: 'сходили', действие: 'ход' },
  { глагол: 'подкидывает', действие: 'подкинул' },
  { глагол: 'подкинули', действие: 'подкинул' },
  { глагол: 'отбивает', действие: 'отбил' },
  { глагол: 'отбили', действие: 'отбил' },
  { глагол: 'переводит', действие: 'перевёл' },
  { глагол: 'перевели', действие: 'перевёл' }
];

/** «10♠», «7♥» и т. п. — то, как игра называет карту в рассказе. */
const РЕГУЛЯРКА_КАРТЫ = /(10|[2-9]|[ВДКТ])([♠♥♦♣])/g;

function ключИзТекстаКарты(текстКарты) {
  const м = /^(10|[2-9]|[ВДКТ])([♠♥♦♣])$/.exec(текстКарты);
  if (!м) return null;
  return м[2] + м[1];   // ключКарты в игре — масть+имя, а в тексте имя+масть
}

/**
 * Разобрать «вид.событие» на кто/что/какая карта.
 * Возвращает null, если событие не про карту (например, «Бито», «Беру» —
 * без {карта}, там классифицировать полёт нечего, эти карты в проверке
 * не нужны — единственная новая карта появляется не тут, а её на столе и так нет).
 */
function разобратьСобытие(текст, моёИмя) {
  if (!текст) return null;
  for (const запись of ГЛАГОЛ_К_ДЕЙСТВИЮ) {
    const где = текст.indexOf(запись.глагол);
    if (где === -1) continue;
    const кто = текст.slice(0, где).trim();
    const хвост = текст.slice(где + запись.глагол.length);
    const карты = хвост.match(РЕГУЛЯРКА_КАРТЫ);
    if (!карты || !карты.length) continue;
    const последняя = карты[карты.length - 1];
    const ключ = ключИзТекстаКарты(последняя);
    if (!ключ) continue;
    const своё = текст.slice(0, где).trim() === 'Вы';
    return {
      действие: запись.действие,
      картаТекст: последняя,
      ключ,
      кто: своё ? моёИмя : кто,
      своё
    };
  }
  return null;
}

/** Номер места по имени — из вид.застолом (свежий на каждый ответ сервера). */
function номерМестаПоИмени(застолом, имя, своё) {
  if (!Array.isArray(застолом)) return null;
  const место = своё
    ? застолом.find((м) => м.этоЯ)
    : застолом.find((м) => м.имя === имя);
  return место && typeof место.номер === 'number' ? место.номер : null;
}

function печатьСобытия(вид, моёИмя) {
  const разбор = разобратьСобытие(вид.событие, моёИмя);
  if (!разбор) return;
  const номерМеста = номерМестаПоИмени(вид.застолом, разбор.кто, разбор.своё);
  const запись = {
    времяМС: Date.now(),
    действие: разбор.действие,
    ключ: разбор.ключ,
    картаТекст: разбор.картаТекст,
    кто: разбор.кто,
    своё: разбор.своё,
    номерМеста,
    сыройТекст: вид.событие
  };
  console.log('Событие: ' + вид.событие + '  →  действие=' + запись.действие +
    ' ключ=' + запись.ключ + ' кто="' + запись.кто + '" номерМеста=' + запись.номерМеста);
  console.log('СОБЫТИЕ_JSON ' + JSON.stringify(запись));
}

