/* =====================================================================
   НАРДЫ ДОРОГОЙ ЧЕЛОВЕКА: витрина → плитка → меню → «Назад» → «Играть».

   Почему проверка идёт именно так. Все прежние проверки нард заходили
   на «нарды.html» напрямую и потому не заметили, что плитка на витрине
   стоит выключенной: игра была готова сутки, а попасть в неё было
   нельзя вовсе. Эта проверка ходит человеческой дорогой и смотрит не
   «страница открылась», а «человек вернулся не хуже, чем ушёл».

   Один маршрут, три вопроса по дороге:
     1) с витрины на нарды можно попасть;
     2) «Назад» приводит на витрину ВМЕСТЕ с адресом сервера — иначе
        в дураке перестанет работать игра с другом, а виноваты будут
        нарды, о которых человек уже забыл;
     3) маленькая кнопка «Играть» на плитке открывает партию сразу и
        в той версии, в которую играли в прошлый раз.

   Хитрость в середине маршрута: перед нажатием «Назад» кладём в память
   телефона ВЧЕРАШНИЙ, уже мёртвый адрес сервера. Без неё проверка
   зеленела бы даром — потерянный хвост незаметно подменялся адресом
   из памяти. А это и есть та самая беда владельца: память держалась
   за вчерашний туннель, и «игру с другом» создать было нельзя.

   И два случая отдельно: новичок (версии в памяти нет — ему обязано
   открыться меню, угадать за человека хуже, чем спросить) и чужой код
   комнаты в ссылке (он принадлежит дураку, обратно нести его нельзя).

   Запуск: node tests/нарды-дорогой-человека.js
   Выход 0 — провалов нет. Раздачу страниц поднимает сама, порт свободный.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const http = require('http');

/* Боевую папку данных не трогаем даже случайно: проверки однажды уже
   стёрли настоящие данные владельца. */
process.env.GAMES_DATA = fs.mkdtempSync(path.join(os.tmpdir(), 'нарды-дорога-'));

const КОРЕНЬ = path.join(__dirname, '..');
const робот = require(path.join(КОРЕНЬ, 'tests', 'браузер-робот.js'));

const ТИПЫ = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.mp3': 'audio/mpeg'
};

/* Адрес нарочно непохожий на настоящий: если он доедет до конца дороги
   в целости, значит несут именно его, а не подставляют запасной
   «этот же компьютер». */
const АДРЕС_СЕРВЕРА = 'https://proverka-nard.trycloudflare.com';
/* Вчерашний туннель: живым он не бывает никогда. Кладём его в память
   нарочно — чтобы потерянный хвост нельзя было прикрыть памятью. */
const ВЧЕРАШНИЙ_АДРЕС = 'https://vcherashniy-tunnel.trycloudflare.com';
const КЛЮЧ_АДРЕСА_В_ПАМЯТИ = 'server_address';
const ЧУЖОЙ_КОД = 'QW34';

let проверок = 0;
const провалы = [];

function проверить(условие, что) {
  проверок++;
  if (условие) { console.log('  ок      ' + что); return; }
  провалы.push(что);
  console.log('  ПРОВАЛ  ' + что);
}

const спать = (мс) => new Promise((готово) => setTimeout(готово, мс));

/** Раздача файлов проекта: браузер-робот не открывает диск напрямую. */
function поднятьРаздачу() {
  const сервер = http.createServer(function (запрос, ответ) {
    let путь = запрос.url.split('?')[0].split('#')[0];
    try { путь = decodeURIComponent(путь); } catch (ошибка) { /* оставим как есть */ }
    const файл = path.join(КОРЕНЬ, путь === '/' ? 'index.html' : путь.slice(1));
    fs.readFile(файл, function (беда, тело) {
      if (беда) { ответ.writeHead(404); ответ.end('нет такого файла'); return; }
      ответ.writeHead(200, { 'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'text/plain' });
      ответ.end(тело);
    });
  });
  return new Promise((готово) => сервер.listen(0, () => готово(сервер)));
}

/** Какие экраны сейчас видны — по тому же признаку, что ставит сама игра. */
function видимыеЭкраны(страница) {
  return страница.evaluate(function () {
    return Array.from(document.querySelectorAll('.экран'))
      .filter(function (экран) { return экран.classList.contains('экран--виден'); })
      .map(function (экран) { return экран.id; }).join(',');
  });
}

/** Нажать узел по имени; отвечает, нашёлся ли он и можно ли было нажать. */
function нажать(страница, имя) {
  return страница.evaluate(function (имяУзла) {
    const узел = document.getElementById(имяУзла);
    if (!узел) return 'нет такого';
    if (узел.disabled) return 'выключен';
    if (узел.classList.contains('скрыт')) return 'спрятан';
    узел.click();
    return 'нажали';
  }, имя);
}

(async function () {
  console.log('=== Нарды дорогой человека ===\n');

  const раздача = await поднятьРаздачу();
  const корень = 'http://127.0.0.1:' + раздача.address().port;
  /* Кода комнаты в этой ссылке нет нарочно: с кодом дурак сразу ведёт
     человека в комнату, минуя витрину, и дороги «витрина → плитка» не
     получится. Чужой код проверяем отдельным заходом, шагом 6. */
  const витрина = корень + '/index.html?сервер=' + encodeURIComponent(АДРЕС_СЕРВЕРА);

  const браузер = await робот.chromium.launch();
  let сбой = null;

  async function новоеОкно() {
    const место = await браузер.newContext({ viewport: { width: 390, height: 780 } });
    const страница = await место.newPage();
    await робот.безTelegram(страница);
    страница.on('pageerror', function (беда) { console.log('   КРАСНАЯ ОШИБКА: ' + беда.message); });
    return страница;
  }

  try {
    const человек = await новоеОкно();

    console.log('1. Витрина → плитка «Нарды»');
    await человек.goto(витрина);
    await спать(700);
    проверить((await видимыеЭкраны(человек)).indexOf('экран-витрины') !== -1,
      'открылась витрина «во что играть»');
    проверить(await нажать(человек, 'кнопка-игра-нарды') === 'нажали',
      'плитка «Нарды» живая и нажимается');
    await человек.waitForLoadState('load');
    await спать(900);

    let адресСтраницы = decodeURIComponent(человек.url()).replace(корень, '');
    console.log('   оказались на: ' + адресСтраницы);
    проверить(/нарды\.html/i.test(адресСтраницы), 'открылась страница нард');
    проверить(адресСтраницы.indexOf(АДРЕС_СЕРВЕРА) !== -1,
      'адрес сервера доехал до нард');

    console.log('2. Выбираем длинные нарды — как человек в меню');
    проверить((await видимыеЭкраны(человек)).indexOf('экран-режимов') !== -1,
      'нарды встретили меню');
    проверить(await нажать(человек, 'версия-длинные') === 'нажали', 'кнопка «Длинные» нажалась');
    await спать(300);
    const запомнилось = await человек.evaluate(function () {
      return window.localStorage.getItem('nardy_version');
    });
    console.log('   в памяти нард лежит версия: ' + запомнилось);
    проверить(запомнилось === 'длинные', 'выбор версии запомнился');

    console.log('3. «Назад» — человек возвращается не хуже, чем ушёл');
    /* Портим память нарочно: пусть в ней лежит вчерашний мёртвый туннель.
       Донесём хвост — игра возьмёт свежий адрес из ссылки; не донесём —
       подставит вчерашний, и мы это увидим. */
    await человек.evaluate(function (пара) {
      window.localStorage.setItem(пара.ключ, пара.вчерашний);
    }, { ключ: КЛЮЧ_АДРЕСА_В_ПАМЯТИ, вчерашний: ВЧЕРАШНИЙ_АДРЕС });

    проверить(await нажать(человек, 'кнопка-назад') === 'нажали', 'кнопка «К выбору игры» на месте');
    await человек.waitForLoadState('load');
    await спать(900);

    адресСтраницы = decodeURIComponent(человек.url()).replace(корень, '');
    console.log('   вернулись на: ' + адресСтраницы);
    проверить(/index\.html/i.test(адресСтраницы), '«Назад» приводит на витрину');
    проверить(адресСтраницы.indexOf(АДРЕС_СЕРВЕРА) !== -1,
      'адрес сервера вернулся вместе с человеком');

    const адресУИгры = await человек.evaluate(function () {
      return (window.Сеть && typeof window.Сеть.адрес === 'function') ? window.Сеть.адрес() : '(двери нет)';
    });
    console.log('   игра на витрине считает сервером: ' + адресУИгры);
    проверить(адресУИгры === АДРЕС_СЕРВЕРА,
      'дурак на витрине знает свежий сервер, а не вчерашний (главная проверка)');

    console.log('4. Кнопка «Играть» на плитке — партия сразу и в своей версии');
    проверить(await нажать(человек, 'кнопка-играть-нарды') === 'нажали',
      'кнопка «Играть» на плитке нард видна тому, кто уже играл');
    await человек.waitForLoadState('load');
    await спать(1200);

    адресСтраницы = decodeURIComponent(человек.url()).replace(корень, '');
    console.log('   пошли на: ' + адресСтраницы);
    проверить(/сразу=1/.test(адресСтраницы), 'витрина попросила начать сразу');
    проверить(адресСтраницы.indexOf(АДРЕС_СЕРВЕРА) !== -1, 'и адрес сервера снова несём');

    const экраны = await видимыеЭкраны(человек);
    const заголовок = (await человек.evaluate(function () {
      const узел = document.getElementById('заголовок-игры');
      return узел ? узел.textContent : '';
    })).trim();
    console.log('   видно экранов: ' + экраны + '; заголовок: «' + заголовок + '»');
    проверить(экраны.indexOf('экран-игры') !== -1, 'партия открылась сразу, минуя меню');
    проверить(/^Длинные/.test(заголовок), 'и в той версии, в которую играли в прошлый раз');

    console.log('5. Новичку «сразу» открывает меню, а не угадывает за него');
    const новичок = await новоеОкно();
    await новичок.goto(корень + '/нарды.html?сразу=1');
    await спать(1000);
    const уНовичка = await видимыеЭкраны(новичок);
    console.log('   видно экранов: ' + уНовичка);
    проверить(уНовичка.indexOf('экран-режимов') !== -1,
      'версии не помним — открыли меню, а не угадали');
    проверить(уНовичка.indexOf('экран-игры') === -1, 'и партию новичку не навязали');

    console.log('6. Чужой код комнаты на витрину не уносим');
    /* Код комнаты принадлежит одной игре. Принеси мы дуракский код обратно —
       витрина примет его за приглашение и полезет в чужую комнату. */
    const сКодом = await новоеОкно();
    await сКодом.goto(корень + '/нарды.html?сервер=' + encodeURIComponent(АДРЕС_СЕРВЕРА) + '&код=' + ЧУЖОЙ_КОД);
    await спать(900);
    проверить(await нажать(сКодом, 'кнопка-назад') === 'нажали', 'из нард можно уйти назад');
    await сКодом.waitForLoadState('load');
    await спать(700);
    const сКодомВернулись = decodeURIComponent(сКодом.url()).replace(корень, '');
    console.log('   вернулись на: ' + сКодомВернулись);
    проверить(сКодомВернулись.indexOf(ЧУЖОЙ_КОД) === -1, 'чужой код комнаты остался позади');
    проверить(сКодомВернулись.indexOf(АДРЕС_СЕРВЕРА) !== -1, 'а адрес сервера всё равно донесли');
  } catch (беда) {
    сбой = беда;
  }

  await браузер.close();
  раздача.close();

  console.log('\n----------------------------------------');
  if (сбой) console.log('ОБОРВАЛОСЬ: ' + сбой.stack);
  console.log('Проверок сделано: ' + проверок);
  console.log('ПРОВАЛОВ: ' + провалы.length);
  провалы.forEach(function (что) { console.log('  · ' + что); });
  process.exit(провалы.length === 0 && !сбой ? 0 : 1);
})();
