/** Какие экраны видны, есть ли нижняя полоса вкладок. */
async function вид(страница) {
  return страница.evaluate(() => {
    const видно = (э) => {
      const с = getComputedStyle(э), р = э.getBoundingClientRect();
      return с.display !== 'none' && с.visibility !== 'hidden' && р.width > 0 && р.height > 0;
    };
    const экраны = Array.from(document.querySelectorAll('section.экран')).filter(видно).map((э) => э.id);
    const вкладки = Array.from(document.querySelectorAll('.нижние-вкладки')).filter(видно).length;
    return { экраны: экраны, вкладок: вкладки };
  });
}

const видимыйЭкран = (страница, id) => страница.evaluate((и) => {
  const э = document.getElementById(и);
  if (!э) return false;
  const с = getComputedStyle(э), р = э.getBoundingClientRect();
  return с.display !== 'none' && с.visibility !== 'hidden' && р.width > 0 && р.height > 0;
}, id);

async function ждатьЭкран(страница, id, мс) {
  try {
    await страница.waitForFunction((и) => {
      const э = document.getElementById(и);
      if (!э) return false;
      const с = getComputedStyle(э), р = э.getBoundingClientRect();
      return с.display !== 'none' && с.visibility !== 'hidden' && р.width > 0 && р.height > 0;
    }, id, { timeout: мс || 8000 });
    return true;
  } catch (е) { return false; }
}

/** Нажать на узел по id; не нашли или не виден — красная строка с именем узла. */
async function нажать(страница, id, что) {
  const у = страница.locator('#' + id);
  try {
    await у.waitFor({ state: 'visible', timeout: 6000 });
    await у.click({ timeout: 4000 });
    return true;
  } catch (е) {
    проверить(false, что + ': не нашёл видимую кнопку #' + id);
    return false;
  }
}

/** Ждём код комнаты на экране ожидания (не точки «····»). */
async function прочитатьКод(страница) {
  try {
    await страница.waitForFunction(() => {
      const у = document.getElementById('код-комнаты');
      return Boolean(у) && /^[A-Za-z0-9]{4,}$/.test(у.textContent.trim());
    }, null, { timeout: 10000 });
    return (await страница.locator('#код-комнаты').textContent()).trim();
  } catch (е) { return ''; }
}

/** Из лобби до комнаты ожидания: «Играть онлайн» -> «Создать игру». Возвращает код или ''. */
async function создатьСтол(страница, игра) {
  if (!(await нажать(страница, 'лобби-найти-игру', игра + ': вход в онлайн'))) return '';
  if (!(await нажать(страница, 'открытые-столы-создать', игра + ': «Создать игру»'))) return '';
  return прочитатьКод(страница);
}

