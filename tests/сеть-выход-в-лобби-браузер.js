async function прогнатьИгру(б, игра, стенд, ошибки) {
  const адрес = (доп) => 'http://127.0.0.1:' + стенд.портСтраниц + '/' + encodeURI(игра.страница) + '?server=' + encodeURIComponent('http://127.0.0.1:' + стенд.портКомнат) + (доп || '');
  const открыть = async () => {
    const к = await б.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
    const с = await к.newPage();
    await безTelegram(с);
    /* Скрипт telegram-web-app.js мы сами не пускаем (безTelegram) — браузер пишет про это
       «Failed to load resource: net::ERR_FAILED». Это шум стенда, а не ошибка игры: считаем
       такие отказы по каждой странице и вычитаем из ошибок консоли в конце. */
    с.on('requestfailed', (з) => { if (з.url().includes('telegram-web-app.js')) стенд.аборты.set(с, (стенд.аборты.get(с) || 0) + 1); });
    с.on('pageerror', (е) => ошибки.push({ страница: с, игра: игра.имя, сценарий: текущийСценарий, текст: 'pageerror: ' + е.message }));
    с.on('console', (с2) => { if (с2.type() === 'error') ошибки.push({ страница: с, игра: игра.имя, сценарий: текущийСценарий, текст: с2.text() }); });
    return { к: к, с: с };
  };

  /* --- 1 и 5 --- */
  текущийСценарий = игра.имя + '|1';
  console.log('\n[' + игра.имя + '] сценарий 1: лобби -> создать стол -> «Выйти из комнаты»');
  {
    const { к, с } = await открыть();
    await с.goto(адрес());
    проверить(await ждатьЭкран(с, 'экран-лобби', 8000), игра.имя + ': страница открылась сразу в лобби');
    const код1 = await создатьСтол(с, игра.имя);
    проверить(код1 !== '', игра.имя + ': комната ожидания показала код (' + код1 + ')');
    проверить(await видимыйЭкран(с, 'экран-комнаты'), игра.имя + ': виден экран комнаты');
    if (await нажать(с, 'кнопка-комната-отмена', игра.имя + ': выход из комнаты')) await ждёмЛобби(с, игра.имя, 'после выхода');
    await снимок(с, игра.имя + '-1-лобби');

    текущийСценарий = игра.имя + '|5';
    console.log('[' + игра.имя + '] сценарий 5: после возврата в лобби создать стол ещё раз');
    const код2 = await создатьСтол(с, игра.имя);
    проверить(код2 !== '' && код2 !== код1, игра.имя + ': второй стол создан, код новый (' + код1 + ' -> ' + код2 + ')');
    if (await нажать(с, 'кнопка-комната-отмена', игра.имя + ': второй выход')) await ждёмЛобби(с, игра.имя, 'после второго выхода');
    await снимок(с, игра.имя + '-5-второй-стол');
    await к.close();
  }

  /* --- 2 --- */
  текущийСценарий = игра.имя + '|2';
  console.log('\n[' + игра.имя + '] сценарий 2: создать стол -> перезагрузка -> «Вернуться к игре» -> «Выйти»');
  {
    const { к, с } = await открыть();
    await с.goto(адрес());
    const код = await создатьСтол(с, игра.имя);
    проверить(код !== '', игра.имя + ': стол создан (' + код + ')');
    await с.reload();
    проверить(await ждатьЭкран(с, 'экран-лобби', 8000), игра.имя + ': после перезагрузки виден #экран-лобби');
    let плашка = false;
    try { await с.locator('#кнопка-вернуться-в-игру').waitFor({ state: 'visible', timeout: 8000 }); плашка = true; } catch (е) { /* красная строка ниже */ }
    проверить(плашка, игра.имя + ': в лобби видна плашка #кнопка-вернуться-в-игру');
    if (плашка) {
      await с.locator('#кнопка-вернуться-в-игру').click();
      проверить(await ждатьЭкран(с, 'экран-комнаты', 8000), игра.имя + ': по плашке вернулись в комнату');
      if (await нажать(с, 'кнопка-комната-отмена', игра.имя + ': выход после возврата')) await ждёмЛобби(с, игра.имя, 'после возврата и выхода');
    }
    await снимок(с, игра.имя + '-2-после-возврата');
    await к.close();
  }

  /* --- 3 --- */
  текущийСценарий = игра.имя + '|3';
  console.log('\n[' + игра.имя + '] сценарий 3: создать стол -> сервер комнат погашен и поднят пустым (комната пропала)');
  {
    const { к, с } = await открыть();
    await с.goto(адрес());
    const код = await создатьСтол(с, игра.имя);
    проверить(код !== '', игра.имя + ': стол создан (' + код + ')');
    await стенд.перезапуститьКомнаты();
    console.log('  сервер комнат перезапущен с пустыми данными, жду, пока страница заметит');
    await ждёмЛобби(с, игра.имя, 'после пропажи комнаты');
    const текст = await с.evaluate(() => document.body.innerText.trim().length);
    проверить(текст > 20, игра.имя + ': экран не пустой (знаков текста: ' + текст + ')');
    await снимок(с, игра.имя + '-3-комната-пропала');
    await к.close();
  }

  /* --- 4 --- */
  текущийСценарий = игра.имя + '|4';
  console.log('\n[' + игра.имя + '] сценарий 4: вход по ссылке-приглашению -> «Выйти»');
  {
    const хозяин = await открыть();
    await хозяин.с.goto(адрес());
    const код = await создатьСтол(хозяин.с, игра.имя);
    проверить(код !== '', игра.имя + ': хозяин создал стол (' + код + ')');
    const гость = await открыть();
    await гость.с.goto(адрес('&код=' + код));
    // По ссылке гость входит сам: либо видит комнату, либо партия уже началась (два места — два человека).
    let место = '';
    try {
      await гость.с.waitForFunction(() => {
        const в = (и) => { const э = document.getElementById(и); if (!э) return false; const р = э.getBoundingClientRect(); return getComputedStyle(э).display !== 'none' && р.width > 0; };
        return в('экран-комнаты') ? 'комната' : (в('экран-шашек') ? 'шашки' : (в('экран-игры') ? 'игра' : false));
      }, null, { timeout: 12000 });
      место = (await вид(гость.с)).экраны.join(', ');
    } catch (е) { /* красная строка ниже */ }
    проверить(место !== '', игра.имя + ': гость по ссылке попал в комнату или за стол (виден: ' + (место || 'ничего') + ')');
    if (место) {
      console.log('  гость видит: ' + место);
      // Выход: из комнаты — кнопкой «Выйти из комнаты»; из начатой партии — «В меню» и подтверждение.
      if (await видимыйЭкран(гость.с, 'экран-комнаты')) {
        await нажать(гость.с, 'кнопка-комната-отмена', игра.имя + ': гость выходит из комнаты');
      } else {
        const выйти = гость.с.locator('#кнопка-в-меню-шашки:visible, #кнопка-в-меню:visible, [id*="в-меню"]:visible').first();
        try { await выйти.click({ timeout: 5000 }); } catch (е) { проверить(false, игра.имя + ': гость: не нашёл кнопку «В меню» за столом'); }
        const подтвердить = гость.с.getByRole('button', { name: /^(Выйти|Да|Покинуть|Выйти из партии)/ }).first();
        try { await подтвердить.click({ timeout: 3000 }); } catch (е) { /* подтверждения может не быть */ }
      }
      await ждать(1500);
      const в = await вид(гость.с);
      проверить(в.экраны.includes('экран-друга'), игра.имя + ': по ссылке выход ведёт на «Игра с другом» (видны: ' + (в.экраны.join(', ') || 'ни одного') + ')');
      проверить(!в.экраны.includes('экран-лобби'), игра.имя + ': лобби при этом не показано');
    }
    await снимок(гость.с, игра.имя + '-4-по-ссылке');
    // Хозяин уходит, чтобы не висел стол.
    try { if (await видимыйЭкран(хозяин.с, 'экран-комнаты')) await хозяин.с.locator('#кнопка-комната-отмена').click({ timeout: 3000 }); } catch (е) { /* не важно */ }
    await гость.к.close(); await хозяин.к.close();
  }
}

