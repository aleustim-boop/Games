function свободныйПорт() {
  return new Promise((готово, беда) => {
    const с = net.createServer();
    с.on('error', беда);
    с.listen(0, '127.0.0.1', () => { const п = с.address().port; с.close(() => готово(п)); });
  });
}

const ТИПЫ = { '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8', '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg',
  '.webp': 'image/webp', '.woff2': 'font/woff2', '.mp3': 'audio/mpeg', '.ogg': 'audio/ogg', '.wav': 'audio/wav' };

/** Сервер страниц: отдаёт файлы проекта; «подмены» — путь (от корня, с «/») -> текст. Токены и точки — нет. */
function поднятьСерверСтраниц(подмены) {
  const сервер = http.createServer((запрос, ответ) => {
    let адрес;
    try { адрес = decodeURIComponent(запрос.url.split('?')[0]); } catch (е) { ответ.writeHead(400); ответ.end(); return; }
    if (адрес === '/') адрес = '/index.html';
    if (/\.env|(^|\/)\./i.test(адрес) || /^\/bot(\/|$)/i.test(адрес)) { ответ.writeHead(403); ответ.end('закрыто'); return; }
    const заголовки = (файл) => ({ 'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'application/octet-stream', 'Cache-Control': 'no-store' });
    if (подмены[адрес] !== undefined) { ответ.writeHead(200, заголовки(адрес)); ответ.end(подмены[адрес]); return; }
    const файл = path.resolve(path.join(КОРЕНЬ, адрес));
    if (!файл.startsWith(path.resolve(КОРЕНЬ) + path.sep)) { ответ.writeHead(403); ответ.end(); return; }
    fs.readFile(файл, (ошибка, данные) => {
      if (ошибка) { ответ.writeHead(404); ответ.end('нет'); return; }
      ответ.writeHead(200, заголовки(файл)); ответ.end(данные);
    });
  });
  return new Promise((готово) => сервер.listen(0, '127.0.0.1', () => готово(сервер)));
}

/** Свой сервер комнат: свой порт, своя временная папка данных, «--без-памяти». Гасим по PID. */
function поднятьСерверКомнат(порт, папкаДанных) {
  const дитя = spawn(process.execPath, [path.join(КОРЕНЬ, 'server', 'сервер.js'), String(порт), '--без-памяти'],
    { stdio: 'pipe', env: Object.assign({}, process.env, { ДАННЫЕ_ИГРЫ: папкаДанных }) });
  return new Promise((готово, беда) => {
    let вывод = '', ошибки = '';
    const т = setTimeout(() => беда(new Error('сервер комнат не поднялся за 10с. Вывод: ' + вывод + ' Ошибки: ' + ошибки)), 10000);
    дитя.stdout.on('data', (д) => { вывод += д.toString(); if (вывод.includes('работает')) { clearTimeout(т); готово(дитя); } });
    дитя.stderr.on('data', (д) => { ошибки += д.toString(); });
    дитя.on('exit', (код) => { clearTimeout(т); беда(new Error('сервер комнат вышел с кодом ' + код + '. ' + ошибки)); });
  });
}

function погасить(дитя) {
  return new Promise((готово) => {
    if (!дитя || дитя.exitCode !== null) { готово(); return; }
    дитя.removeAllListeners('exit');
    дитя.once('exit', () => готово());
    try { process.kill(дитя.pid); } catch (е) { готово(); }
    setTimeout(готово, 3000);
  });
}

