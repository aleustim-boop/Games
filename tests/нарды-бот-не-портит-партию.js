'use strict';

/* =====================================================================
   НАРДЫ: БОТ ДУМАЕТ НА КОПИИ, А НЕ НА НАСТОЯЩЕЙ ПАРТИИ.

   ОТКУДА ПРОВЕРКА. Владелец играл в длинные нарды против уровня
   «мастер» и увидел: его ход, кубики 5 и 6, ни один не сыгран, пятый
   пункт от головы свободен — а шашки на голове не подсвечены, ходят
   только другие. Первое подозрение было на самого «мастера»: он
   единственный перебирает все 21 броска соперника на копиях партии и
   единственный пользуется быстрой дверью правил «разыгратьГотовыйХод».
   Если бы копия делила с оригиналом хоть один список (кубики, сыграно,
   «сколько взято с головы»), настоящая партия портилась бы молча.

   Разбор показал, что мастер партию не портит, а ход с головы убирает
   обычное правило «сыграй столько кубиков, сколько можешь»: после хода
   с головы второй кубик оказывался несыгранным, а другим ходом играются
   оба. Правило верное, менять было нечего — но и оставлять такие вещи
   на «мы посмотрели глазами» нельзя. Эта проверка закрепляет сразу оба
   утверждения, чтобы завтрашняя правка бота не сломала их тихо.

   ЧТО ПРОВЕРЯЕТСЯ

     1. Мысли не меняют партию. Перед каждым вызовом Бот.выбратьХод
        снимается JSON партии, после — сравнивается. Байт в байт.
     2. Боту достаётся только копия. Партия отдаётся боту замороженной
        (Object.freeze до самого дна): любая попытка записать во вход в
        строгом режиме бросает ошибку, молча испортить нельзя.
     3. После хода бота голова открыта. Бот ходит за чёрных, очередь
        переходит к белым, у белых 5 и 6 — ход с головы обязан быть в
        списке. И тот же ход, применённый к копии, сделанной ДО раздумий
        бота, обязан дать ровно тот же список ходов.
     4. Голову закрывает только правило обоих кубиков. Позиция владельца
        (большая стопка на голове, пятый пункт свободен, ход с головы не
        предлагается): если временно снять требование играть оба кубика,
        ход с головы появляется. Значит запрет именно оттуда, а не от
        лимита головы и не от забора из шести.

   ЗАПУСК

     node tests/нарды-бот-не-портит-партию.js

   ЛОМАЮЩИЕ ЗАПУСКИ (проверка обязана покраснеть)

     node tests/нарды-бот-не-портит-партию.js --сломать
        Правилам подменяется «копияПартии»: теперь она возвращает сам
        объект, а не копию. Бот начинает думать прямо на настоящей
        партии — проверки 1 и 2 обязаны покраснеть.

     node tests/нарды-бот-не-портит-партию.js --сломать-голову
        В проверках 3 и 4 после броска обнуляется лимит головы — то
        есть подделывается ровно та поломка, на которую жаловался
        владелец. Проверка 3 обязана покраснеть.

   КОД ВОЗВРАТА. 0 — всё в порядке (при ломающем запуске 0 значит
   «покраснела, как и должна»). 1 — провал.
   ===================================================================== */

const путь = require('path');
const КОРЕНЬ = путь.join(__dirname, '..');
const Правила = require(путь.join(КОРЕНЬ, 'js', 'нарды-правила.js'));
const Бот = require(путь.join(КОРЕНЬ, 'js', 'нарды-бот.js'));
const Генератор = require(путь.join(КОРЕНЬ, 'tests', 'общий-генератор.js'));

const слова = process.argv.slice(2);
const ломаемКопию = слова.indexOf('--сломать') !== -1;
const ломаемГолову = слова.indexOf('--сломать-голову') !== -1;
const ломаем = ломаемКопию || ломаемГолову;

const ЗЕРНО = 20260916;
const ПАРТИЙ_ДЛИННЫХ = 3;
const ПАРТИЙ_КОРОТКИХ = 2;
const ХОДОВ_МАКСИМУМ = 400;

/* Подмена копии — тот самый ломающий запуск. Бот зовёт копию через
   объект дверей («Правила.копияПартии»), поэтому подмена ему видна, а
   внутренние вызовы самих правил остаются настоящими. */
if (ломаемКопию) {
  Правила.копияПартии = function (партия) { return партия; };
}

/** Бросок с обнулением лимита головы — подделка поломки со снимка. */
function бросить(партия, кубики) {
  const выпало = Правила.бросить(партия, кубики);
  if (ломаемГолову) партия.лимитГоловы = 0;
  return выпало;
}

let провалов = 0;
function проверить(что, вышло, пояснение) {
  if (!вышло) провалов++;
  console.log((вышло ? '  OK  ' : '  БЕДА') + '  ' + что + (пояснение ? ' — ' + пояснение : ''));
}

/* Кубик из повторимого потока: то же зерно — тот же прогон. */
const поток = Генератор.создатьПоток(ЗЕРНО);
function кубик() { return 1 + Math.floor(поток() * 6); }

/* =====================================================================
   ПРОВЕРКА 1. Мысли мастера не меняют партию
   ===================================================================== */

function мыслиНеМеняютПартию() {
  let вызовов = 0;
  let расхождений = 0;
  let первое = '';

  const виды = [];
  for (let i = 0; i < ПАРТИЙ_ДЛИННЫХ; i++) виды.push(Правила.ДЛИННЫЕ);
  for (let i = 0; i < ПАРТИЙ_КОРОТКИХ; i++) виды.push(Правила.КОРОТКИЕ);

  for (const вид of виды) {
    const п = Правила.создатьПартию({ вид: вид, первый: Правила.БЕЛЫЕ });
    let ходов = 0;
    while (!Правила.партияЗавершена(п) && ходов < ХОДОВ_МАКСИМУМ) {
      Правила.бросить(п, [кубик(), кубик()]);
      const до = JSON.stringify(п);
      let ход = null;
      try {
        ход = Бот.выбратьХод(п, 'мастер');
      } catch (е) {
        расхождений++;
        if (!первое) первое = 'бот упал: ' + е.message;
        break;
      }
      вызовов++;
      const после = JSON.stringify(п);
      if (до !== после) {
        расхождений++;
        if (!первое) первое = 'партия изменилась после раздумий (' + вид + ', ход ' + ходов + ')';
      }
      /* Ход применяется полной дверью правил: заодно видно, что бот не
         предлагает ничего незаконного. */
      if (ход) {
        if (!Правила.сделатьХод(п, ход)) {
          расхождений++;
          if (!первое) первое = 'правила не приняли ход бота';
          break;
        }
      } else if (!Правила.завершитьХод(п)) {
        расхождений++;
        if (!первое) первое = 'ходов нет, а очередь не передаётся';
        break;
      }
      ходов++;
    }
  }

  проверить('мысли мастера не меняют партию (' + вызовов + ' вызовов)',
    расхождений === 0, расхождений ? первое : 'JSON до и после совпал везде');
}

/* =====================================================================
   ПРОВЕРКА 2. Боту достаётся только копия (заморозка)
   ===================================================================== */

function заморозить(о) {
  if (о && typeof о === 'object' && !Object.isFrozen(о)) {
    Object.freeze(о);
    for (const ключ of Object.keys(о)) заморозить(о[ключ]);
  }
  return о;
}

function ботНеПишетВоВход() {
  let вызовов = 0;
  let попыток = 0;
  let первая = '';

  for (const вид of [Правила.ДЛИННЫЕ, Правила.КОРОТКИЕ]) {
    const п = Правила.создатьПартию({ вид: вид, первый: Правила.БЕЛЫЕ });
    let ходов = 0;
    while (!Правила.партияЗавершена(п) && ходов < ХОДОВ_МАКСИМУМ) {
      Правила.бросить(п, [кубик(), кубик()]);
      /* Боту отдаём замороженный слепок, а партию двигаем настоящим
         ходом — иначе партия не доиграется до конца. */
      const слепок = заморозить(JSON.parse(JSON.stringify(п)));
      вызовов++;
      try {
        Бот.выбратьХод(слепок, 'мастер');
      } catch (е) {
        попыток++;
        if (!первая) первая = вид + ': ' + е.message;
      }
      const ход = Бот.выбратьХод(п, 'мастер');
      if (ход) { if (!Правила.сделатьХод(п, ход)) break; }
      else if (!Правила.завершитьХод(п)) break;
      ходов++;
    }
  }

  проверить('бот ни разу не пишет во вход (' + вызовов + ' вызовов на замороженной партии)',
    попыток === 0, попыток ? первая : 'заморозка выдержала');
}

/* =====================================================================
   ПРОВЕРКА 3. После хода бота голова открыта

   Позиция подобрана так, что чёрным с 3 и 4 не дотянуться до пунктов
   18 и 19: с головы (12) они попадают на 9 и 8, оттуда — на 5. Значит
   ход белых с головы обязан быть возможен, какой бы ход бот ни выбрал.
   ===================================================================== */

function записьШагов(шаги) {
  return шаги.map(function (ш) { return ш.откуда + '/' + ш.куда + '(' + ш.кубик + ')'; }).sort().join(' ');
}

function послеХодаБотаГоловаОткрыта() {
  const начало = Правила.партияИзРасстановки(Правила.ДЛИННЫЕ, {
    ходит: Правила.ЧЁРНЫЕ,
    белые: { 24: 14, 19: 1 },
    чёрные: { 12: 15 },
    ходов: { белые: 1, чёрные: 1 }
  });
  Правила.бросить(начало, [3, 4]);

  /* Чистая копия делается ДО того, как бот что-либо увидел. */
  const чистая = Правила.копияПартии(начало);

  const ход = Бот.выбратьХод(начало, 'мастер');
  if (!ход) { проверить('после хода бота голова открыта', false, 'бот не нашёл хода'); return; }
  if (!Правила.сделатьХод(начало, ход)) {
    проверить('после хода бота голова открыта', false, 'правила не приняли ход бота');
    return;
  }

  /* Тот же ход на чистой копии — по записи, через полную дверь правил. */
  const тотЖе = Правила.найтиХод(чистая, ход.запись);
  if (!тотЖе || !Правила.сделатьХод(чистая, тотЖе)) {
    проверить('после хода бота голова открыта', false, 'не удалось повторить ход бота на чистой копии');
    return;
  }

  бросить(начало, [5, 6]);
  бросить(чистая, [5, 6]);

  const послеРаздумий = Правила.возможныеШаги(начало);
  const безРаздумий = Правила.возможныеШаги(чистая);
  const сГоловы = послеРаздумий.filter(function (ш) { return ш.откуда === 24; });

  проверить('после хода бота ход с головы есть (' + сГоловы.length + ' шт.)',
    сГоловы.length > 0,
    сГоловы.length ? записьШагов(сГоловы) : 'голова не подсвечена: ' + записьШагов(послеРаздумий));
  проверить('список ходов человека тот же, думал бот или нет',
    записьШагов(послеРаздумий) === записьШагов(безРаздумий),
    записьШагов(послеРаздумий) === записьШагов(безРаздумий)
      ? 'совпал' : 'после раздумий: ' + записьШагов(послеРаздумий) + ' | без них: ' + записьШагов(безРаздумий));
}

/* =====================================================================
   ПРОВЕРКА 4. Голову закрывает только правило обоих кубиков

   Это позиция со снимка владельца: у белых десять шашек на голове,
   пятый пункт от головы (19) свободен, кубики 5 и 6 целы — и всё равно
   ход с головы не предлагается. Проверяем, что виновато именно правило
   «играй оба кубика»: стоит временно снять требование, и ход с головы
   появляется.
   ===================================================================== */

function головуЗакрываетПравилоОбоихКубиков() {
  const п = Правила.партияИзРасстановки(Правила.ДЛИННЫЕ, {
    ходит: Правила.БЕЛЫЕ,
    белые: { 24: 10, 23: 1, 15: 1, 8: 1, 4: 1, 1: 1 },
    чёрные: { 12: 7, 22: 1, 18: 1, 17: 1, 13: 1, 9: 1, 7: 2, 2: 1 },
    ходов: { белые: 4, чёрные: 4 }
  });
  бросить(п, [5, 6]);

  const шаги = Правила.возможныеШаги(п);
  const сГоловы = шаги.filter(function (ш) { return ш.откуда === 24; });

  /* Снимаем требование играть оба кубика — больше ничего не трогаем. */
  const без = Правила.копияПартии(п);
  без.максимумКубиков = 1;
  const сГоловыБез = Правила.возможныеШаги(без).filter(function (ш) { return ш.откуда === 24; });

  проверить('пятый пункт от головы свободен, а ход с головы не предлагается',
    Правила.пункт(п, 19).сколько === 0 && сГоловы.length === 0,
    'показано: ' + записьШагов(шаги));
  проверить('запрет идёт от правила «играй оба кубика», а не от головы или забора',
    сГоловыБез.length > 0,
    сГоловыБез.length ? 'без требования ход с головы есть: ' + записьШагов(сГоловыБез)
                      : 'ход с головы не появляется даже без требования — значит виноват лимит головы или забор');
}

