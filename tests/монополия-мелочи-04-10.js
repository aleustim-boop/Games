/* ---------- запуск экрана в поддельном браузере ---------- */
const исходникЭкрана = fs.readFileSync(ПУТЬ_ЭКРАНА, 'utf8');
function запуститьЭкран(память, правила) {
  const документ = Браузер.сделатьДокумент();
  const узлы = Object.create(null);
  // classList.replace есть в браузере, в общей подделке его нет — экран им пользуется
  const создатьУзел = документ.createElement;
  документ.createElement = function (тег) {
    const у = создатьУзел(тег);
    у.classList.replace = function (было, стало) { у.classList.remove(было); у.classList.add(стало); };
    return у;
  };
  const настоящий = документ.getElementById;
  документ.getElementById = function (id) {
    let у = настоящий(id);
    if (!у) {
      у = документ.createElement('div');
      у.id = id;
      // окно-диалог: в браузере у <dialog> есть эти методы и свойство open
      у.close = function () { у.open = false; };
      у.showModal = function () { у.open = true; };
      документ.body.appendChild(у);
    }
    узлы[id] = у;
    return у;
  };
  документ.__заготовки = { P: правила || (ПУТЬ_ЭКРАНА === ЭКРАН ? P : ПРАВИЛА_ПРОЕКТА), Д };
  const заготовка =
    'var crypto = { getRandomValues: function (а) { а[0] = 12345; return а; } };' +
    'var matchMedia = function () { return { matches: true }; };' +
    'var MutationObserver = function () {};' +
    'MutationObserver.prototype.observe = function () {};' +
    'MutationObserver.prototype.disconnect = function () {};' +
    'window.МонополияПравила = document.__заготовки.P;' +
    'window.МонополияДанные = document.__заготовки.Д;' +
    'window.МонополияБот = {};' +
    'window.МонополияПоле = { colors: ["#111", "#222", "#333", "#444", "#555", "#666"], draw: function () {} };' +
    'window.ЛистЕщё = { подключить: function () { return { открыть: function () {} }; } };\n';
  const мир = Браузер.поднять(заготовка + исходникЭкрана, { память, документ, имяФайла: 'игры/монополия/монополия-экран.js' });
  return { мир, узлы, документ };
}

/* ---------- Б. Старое сохранение не роняет загрузку ---------- */
console.log('\n--- Б: старое сохранение со сдачей посреди торгов ---');
/* Реальный журнал ходов из торгов собрать нельзя (здания расставляют не ходами), поэтому
   даём три вида расхождения со старыми правилами: отказ правил, исключение и партию
   без «чей ход» после проигрыша. */
const запись = (ходы) => JSON.stringify({ version: 1, n: 3, seed: 5, actions: ходы, id: 1, result: false });
const виды = [
  {
    название: 'правила отказывают в ходе (ставка вне торгов после сдачи)',
    текст: запись([{ p: 0, move: { type: 'surrender' } }, { p: 1, move: { type: 'bid', amount: 50, id: 6 } }]),
    правила: null,
  },
  {
    название: 'правила падают исключением (не Error)',
    текст: запись([{ p: 0, move: { type: 'surrender' } }]),
    правила: () => Object.assign({}, ПРАВИЛА_ПРОЕКТА, { action: () => { throw 'сбой'; } }),
  },
  {
    название: 'ходы приняты, но партия без «чей ход» (торги без торгов)',
    текст: запись([{ p: 0, move: { type: 'surrender' } }]),
    правила: () =>
      Object.assign({}, ПРАВИЛА_ПРОЕКТА, {
        action: (g, p, m) => {
          ПРАВИЛА_ПРОЕКТА.action(g, p, m);
          g.phase = 'auction';
          g.auction = null;
          return g;
        },
      }),
  },
];
for (const вид of виды) {
  const память = Браузер.сделатьПамять(false);
  память.setItem(КЛЮЧ, вид.текст);
  let э = null;
  let ошибка = null;
  try {
    э = запуститьЭкран(память, вид.правила ? вид.правила() : null);
  } catch (e) {
    ошибка = e;
  }
  отметить(!ошибка, 'Б: экран поднялся без падения — ' + вид.название + (ошибка ? ' (упал: ' + (ошибка.message || ошибка) + ')' : ''));
  if (э) {
    отметить(память.getItem(КЛЮЧ) === null, 'Б: запись сброшена — ' + вид.название);
    отметить(э.мир.ошибкиКонсоли.length === 0, 'Б: в консоли ошибок нет — ' + вид.название + ' (' + JSON.stringify(э.мир.ошибкиКонсоли) + ')');
    отметить(э.узлы['mono-restore-note'] && /не подошла/.test(э.узлы['mono-restore-note'].textContent), 'Б: игроку в лобби сказано, что партия не подошла — ' + вид.название);
    отметить(э.узлы['mono-resume'] && э.узлы['mono-resume'].classList.contains('скрыт'), 'Б: «Продолжить партию» скрыта — партия не открыта полусломанной — ' + вид.название);
  }
}

/* ---------- В. Подсказка про снятую ставку ---------- */
console.log('\n--- В: подсказка «' + ТЕКСТ_ПОДСКАЗКИ + '» ---');
function собратьТекст(узел) {
  return узел.textContent;
}
function показатьТорги(g) {
  const э = запуститьЭкран(Браузер.сделатьПамять(false));
  const вид = ПРАВИЛА_ПРОЕКТА.view(g, 0);
  э.мир.окно.ИграПоСети.показатьВид({ монополия: вид, код: 'тест', версия: 1, сыграноПартий: 0 });
  const панель = э.документ.getElementById('mono-actions');
  return { э, панель };
}
try {
  // Торги за здание, сдался один из участников: торги продолжились.
  const g = стол(202, 4);
  P.action(g, 0, { type: 'build', id: 16 });
  P.action(g, P.who(g), { type: 'bid', amount: 50, id: 16 });
  P.action(g, P.who(g), { type: 'bid', amount: 60, id: 6 });
  сдаться(g, 0); // сдаётся лидер-участник торгов
  отметить(g.phase === 'auction' && g.auction.building, 'В: после сдачи торги за здание продолжаются');
  let р;
  try {
    р = показатьТорги(g);
  } catch (e) {
    отметить(false, 'В: экран не отрисовал торги: ' + (e.stack || e.message));
  }
  if (р) {
    const строка = р.панель.children.find((у) => собратьТекст(у) === ТЕКСТ_ПОДСКАЗКИ);
    if (отметить(Boolean(строка), 'В: на экране торгов есть строка «' + ТЕКСТ_ПОДСКАЗКИ + '»')) {
      отметить(строка.classList.contains('сеть-сообщение'), 'В: у строки существующий класс «сеть-сообщение» (своего вида из кода нет)');
    }
    отметить(р.панель.dataset.phase === 'auction', 'В: панель действий показывает этап торгов');
  }

  // Контроль: торги без сдачи — подсказки нет.
  const чистая = стол(203, 4);
  P.action(чистая, 0, { type: 'build', id: 16 });
  P.action(чистая, P.who(чистая), { type: 'bid', amount: 50, id: 16 });
  let р2;
  try {
    р2 = показатьТорги(чистая);
  } catch (e) {
    отметить(false, 'В: экран не отрисовал обычные торги: ' + (e.stack || e.message));
  }
  if (р2) {
    отметить(р2.панель.dataset.phase === 'auction', 'В: обычные торги отрисованы (этап «' + р2.панель.dataset.phase + '»)');
    отметить(!р2.панель.children.some((у) => собратьТекст(у) === ТЕКСТ_ПОДСКАЗКИ), 'В: в обычных торгах без сдачи подсказки нет');
  }
} catch (e) {
  отметить(false, 'В: сценарий упал целиком (' + e.message + ')');
}

