function отметить(условие, текст) {
  проверок++;
  console.log((условие ? 'ок — ' : 'ПЛОХО — ') + текст);
  if (!условие) провалов++;
  return условие;
}

/* ---------- стол «последнее здание банка» (раскладка из соседних проверок) ---------- */
const own = (g, p, ids) => ids.forEach((id) => Object.assign(g.properties[id], { owner: p, level: 0 }));
function стол(seed, n) {
  const g = P.create(n, seed);
  g.turn = n >= 4 ? 3 : 0;
  g.phase = 'manage';
  g.queue = [];
  own(g, 0, [16, 18, 19]);
  own(g, 1, [6, 8, 9]);
  own(g, 2, [11, 13, 14]);
  [21, 23, 24, 26, 27, 29, 37].forEach((id) => { g.properties[id].level = 4; });
  g.properties[39].level = 3;
  return g;
}
/* Сдача + пас за чужие аукционы участков, пока они идут (как в соседней проверке). */
function сдаться(g, p) {
  P.action(g, p, { type: 'surrender' });
}

