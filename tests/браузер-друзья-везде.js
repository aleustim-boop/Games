function json(route, тело) {
  return route.fulfill({ status: 200, contentType: 'application/json; charset=utf-8', body: JSON.stringify(тело) });
}

/** Один диспетчер на ВЕСЬ трафик страницы — второй перехватить() не заводим
 *  (правило из tests/браузер-друзья-экран.js: работает только последний). */
async function диспетчер(route, request, адрес) {
  if (подменаДрузьяЭкран && /\/js\/друзья-экран\.js(?:\?|$)/.test(адрес)) {
    await route.fulfill({
      status: 200, contentType: 'text/javascript; charset=utf-8', body: fs.readFileSync(подменаДрузьяЭкран)
    });
    return;
  }
  // Свой файловый сервер страниц — пропускаем как есть.
  if (адрес.indexOf(АДРЕС_СТРАНИЦ) === 0) { route.continue(); return; }

  if (/\/друзья-список(?:\?|$)/.test(адрес)) {
    await json(route, { ок: true, узналиВас: true, друзья: ДРУЗЬЯ_СПИСОК, входящие: [] });
    return;
  }
  if (/\/друзья-онлайн(?:\?|$)/.test(адрес)) {
    await json(route, { ок: true, узналиВас: true, меняВидно: true, друзья: ПРИСУТСТВИЕ, входящихЗаявок: 0 });
    return;
  }
  if (/\/знакомые(?:\?|$)/.test(адрес)) {
    await json(route, { узналиВас: true, знакомые: [], свежий: true });
    return;
  }
  /* Всё прочее: боевой 127.0.0.1:8790 (js/популярность.js, js/мой-аватар.js,
     js/пульс.js), а на нардах/катане/покере ещё js/открытые-столы.js,
     js/подбор-экран.js, js/похвастаться.js и подобные — их ответ ни один
     из наших шагов не читает, важно только не дать браузеру отказ связи
     и не пустить его на боевой сервер. */
  await json(route, { ок: false });
}

/* ---------------------------------------------------------------------
   Свой файловый сервер для страниц игры
   --------------------------------------------------------------------- */
function постучать(адрес) {
  return new Promise(function (готово) {
    const з = http.get(адрес, function (о) { о.resume(); готово(о.statusCode); });
    з.on('error', () => готово(0));
    з.setTimeout(1500, function () { з.destroy(); готово(0); });
  });
}
async function дождатьсяСтраниц() {
  for (let п = 0; п < 40; п++) {
    if (await постучать(АДРЕС_СТРАНИЦ + '/index.html')) return true;
    await new Promise((г) => setTimeout(г, 150));
  }
  return false;
}

/* ---------------------------------------------------------------------
   Консоль браузера
   --------------------------------------------------------------------- */
function следитьЗаКонсолью(страница, красные) {
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const текст = м.text();
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js|telegram\.org/.test(текст + ' ' + откуда)) return;
    красные.push('консоль: ' + текст + (откуда ? ' (' + откуда + ')' : ''));
  });
}

async function дождатьсяЭкрана(страница, id, мс) {
  try {
    await страница.waitForFunction(function (и) {
      const э = document.getElementById(и);
      return Boolean(э && э.classList.contains('экран--виден'));
    }, id, { timeout: мс || 8000 });
    return true;
  } catch (сбой) { return false; }
}

