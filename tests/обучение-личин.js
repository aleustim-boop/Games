'use strict';
/* =====================================================================
   ОБУЧЕНИЕ ЛИЧИН НА ПАРТИЯХ ЛЮДЕЙ (server/обучение.js, копия igra2).

   Проверяем (только node, книга — во временной папке данных):
     1) шашки: ход человека, дважды приведший к победе, личина из той же
        позиции играет сама (жребий «книгу смотрим» — да); ход проходит
        правила шашек;
     2) ход, который вёл к поражению, книга не советует;
     3) в незнакомой позиции подсказки нет — ходит обычный бот;
     4) жребий «книгу не смотрим» (доля 1 − ДОЛЯ_КНИГИ) — подсказки нет;
     5) шахматы: то же, что п.1;
     6) брошенная игра (не шашки/шахматы) ничего не записывает;
     7) книга сохраняется в файл и читается заново после «перезапуска».
   Запуск:  node tests/обучение-личин.js
   Ломающий запуск:  node tests/обучение-личин.js --сломать
     — в памяти подменяем закрепить(): исход записывается как «поражение»
       всегда — обязаны покраснеть пункты 1, 5, 7.
   ===================================================================== */

const path = require('path');
const os = require('os');
const fs = require('fs');

process.env.ДАННЫЕ_ИГРЫ = path.join(os.tmpdir(), 'обучение-личин-' + process.pid);
const КОРЕНЬ = path.join(__dirname, '..');
const СЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;

const ПУТЬ_ОБУЧЕНИЯ = path.join(КОРЕНЬ, 'server', 'обучение.js');
function загрузитьОбучение() {
  delete require.cache[ПУТЬ_ОБУЧЕНИЯ];
  const м = require(ПУТЬ_ОБУЧЕНИЯ);
  if (СЛОМАТЬ) {
    const настоящее = м.закрепить;
    м.закрепить = function (игра, снимки) { return настоящее(игра, снимки, function () { return 'поражение'; }); };
  }
  return м;
}
let обучение = загрузитьОбучение();
const Шашки = require(path.join(КОРЕНЬ, 'server', 'игры', 'шашки.js'));
const ПравилаШашек = require(path.join(КОРЕНЬ, 'js', 'шашки-правила.js'));
const Шахматы = require(path.join(КОРЕНЬ, 'server', 'игры', 'шахматы.js'));
const ПравилаШахмат = require(path.join(КОРЕНЬ, 'js', 'шахматы-правила.js'));

let проверок = 0;
const провалы = [];
function проверить(условие, что) {
  проверок++;
  if (!условие) { провалы.push(что); console.log('  ПРОВАЛ: ' + что); }
}
const всегдаДа = function () { return 0; };        // жребий 0 — «книгу смотрим», первый кандидат
const всегдаНет = function () { return 0.999; };   // жребий выше доли — «книгу не смотрим»

if (СЛОМАТЬ) console.log('*** ЛОМАЮЩИЙ ЗАПУСК: исход всегда «поражение» — проверка обязана покраснеть ***');
console.log('=== Обучение личин ===');

// 1) Шашки.
const п1 = Шашки.раздать('a', { игроки: ['a', 'b'] });
const ходы = ПравилаШашек.возможныеХоды(п1.доска);
const хороший = ходы[ходы.length - 1];
const плохой = ходы[0];
function намерениеШашек(х) {
  return { действие: 'ход', откуда: х.откуда, куда: х.куда, побитые: х.побитые, станетДамкой: х.станетДамкой };
}
for (let партия = 0; партия < 2; партия++) {
  const снимок = обучение.снимок('шашки', п1, 'a', намерениеШашек(хороший));
  проверить(Boolean(снимок), 'шашки: снимок хода человека сделан');
  обучение.закрепить('шашки', [снимок], function () { return 'победа'; });
}
const совет = обучение.подсказка('шашки', п1, всегдаДа);
проверить(совет && совет.откуда === хороший.откуда && совет.куда === хороший.куда,
  'шашки: личина играет ход людей-победителей (' + JSON.stringify(совет) + ')');
if (совет) {
  const копия = Шашки.раздать('a', { игроки: ['a', 'b'] });
  const ответ = Шашки.сделатьХод(копия, 'a', совет);
  проверить(ответ && ответ.принято, 'шашки: ход из книги принят правилами');
}

// 2) Ход, ведущий к поражению, — не советуется.
обучение.забытьВсё();
for (let партия = 0; партия < 3; партия++) {
  обучение.закрепить('шашки', [обучение.снимок('шашки', п1, 'a', намерениеШашек(плохой))], function () { return 'поражение'; });
}
проверить(обучение.подсказка('шашки', п1, всегдаДа) === null, 'шашки: проигрышный ход книга не советует');

// 3) Незнакомая позиция.
const п2 = Шашки.раздать('a', { игроки: ['a', 'b'] });
Шашки.сделатьХод(п2, 'a', намерениеШашек(ПравилаШашек.возможныеХоды(п2.доска)[0]));
проверить(обучение.подсказка('шашки', п2, всегдаДа) === null, 'шашки: в незнакомой позиции подсказки нет');

// 4) Жребий «не смотрим».
обучение.забытьВсё();
for (let партия = 0; партия < 2; партия++) {
  обучение.закрепить('шашки', [обучение.снимок('шашки', п1, 'a', намерениеШашек(хороший))], function () { return 'победа'; });
}
проверить(обучение.подсказка('шашки', п1, всегдаНет) === null, 'шашки: доля без книги — подсказки нет');

// 5) Шахматы.
const ч1 = Шахматы.раздать('a', { игроки: ['a', 'b'] });
const ктоБелые = Шахматы.чейХод(ч1);
const ходШахмат = ПравилаШахмат.возможныеХоды(ч1.позиция).find(function (х) { return х.откуда === 'e2' && х.куда === 'e4'; });
проверить(Boolean(ходШахмат), 'шахматы: ход e2-e4 найден среди законных');
for (let партия = 0; партия < 2; партия++) {
  обучение.закрепить('шахматы', [обучение.снимок('шахматы', ч1, ктоБелые, { действие: 'ход', откуда: 'e2', куда: 'e4' })], function () { return 'победа'; });
}
const советШ = обучение.подсказка('шахматы', ч1, всегдаДа);
проверить(советШ && советШ.откуда === 'e2' && советШ.куда === 'e4', 'шахматы: личина играет e2-e4 из книги');
if (советШ) {
  const копия = Шахматы.раздать(ктоБелые, { игроки: ['a', 'b'] });
  const ответ = Шахматы.сделатьХод(копия, Шахматы.чейХод(копия), советШ);
  проверить(ответ && ответ.принято, 'шахматы: ход из книги принят правилами');
}

// 6) Не та игра.
проверить(обучение.снимок('дурак', {}, 'a', { действие: 'ход' }) === null, 'дурак пока не учится — снимка нет');

// 7) Сохранение и чтение.
обучение.сохранитьСейчас();
const файл = path.join(process.env.ДАННЫЕ_ИГРЫ, 'книга-ходов.json');
проверить(fs.existsSync(файл), 'книга сохранилась в файл');
обучение = загрузитьОбучение();
const послеПерезапуска = обучение.подсказка('шахматы', ч1, всегдаДа);
проверить(послеПерезапуска && послеПерезапуска.куда === 'e4', 'после перезапуска книга прочитана заново');

try { fs.rmSync(process.env.ДАННЫЕ_ИГРЫ, { recursive: true, force: true }); } catch (с) { /* пусто */ }
console.log('\nпроверок: ' + проверок + ', провалов: ' + провалы.length);
process.exit(провалы.length ? 1 : 0);
