// Проверка П18: таблички областей, пилюля «+N» над фигуркой и подписи областей на карте «Остров» (ширина 320).
// Запуск:  node tests/захват-таблички.js            — обычный прогон (без браузера)
//          node tests/захват-таблички.js --сломать  — портит КОПИИ стола во временной папке и требует провала
// Довод --файл <путь> — взять порченую копию игры/захват/захват-стол.js.
// Держим: центр таблички = центр области + (0; 0,22·296·масштаб); «+N» стоит над фигуркой с зазором 2 px;
// подпись области не налезает ни на одну рамку «фигурка + табличка».
// Разметка и поддельный документ — из tests/захват-основа-стола.js.
'use strict';
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const а = process.argv.slice(2);
const довод = (имя) => { const и = а.indexOf(имя); return и === -1 ? null : а[и + 1]; };
const путьСтола = довод('--файл') || path.join(КОРЕНЬ, 'игры', 'захват', 'захват-стол.js');

if (а.includes('--сломать')) сломать();
else process.exit(прогон());

function прогон() {
  const с = require('./захват-основа-стола.js')(путьСтола);
  const { Правила, ЗахватСтол, Узел, сделатьДокумент, узлыКласса, номераОбластейУ, проверка } = с;
  const ШИРИНА = 320;
  const документ = сделатьДокумент();
  const партия = Правила.новаяПартия({ игроки: ['a', 'b', 'c'], люди: ['a'] }, function () { return 0.5; });
  проверка('П18: карта партии — Остров', партия.карта === 'остров', String(партия.карта));
  const стол = ЗахватСтол.создать({ документ: документ, слушатели: {} });
  стол.начатьРаунд(партия, 'a', { имена: { a: 'Вы', b: 'Коля', c: 'Маша' } });
  const раскладка = стол.показатьСлой(ШИРИНА);
  const слойУзел = документ.getElementById('захват-слой');
  const окно = документ.getElementById('захват-карта');
  слойУзел.querySelectorAll = function (сел) { return узлыКласса(слойУзел, сел.replace(/^\./, '')); };
  const s = раскладка.геометрия.масштаб;
  const шайбы = раскладка.шайбы;
  проверка('П18: шайбы, таблички и рамки фигур в раскладке есть (ноль найденного — провал)',
    шайбы.length > 0 && раскладка.таблички.length === шайбы.length && раскладка.рамкиФигур.length === шайбы.length);

  // Формула таблички: центр A + (0; 0,22 × 296 × s), допуск 0,5 px.
  const узлыТабличек = узлыКласса(слойУзел, 'захват-шайба');
  проверка('П18: узлов табличек столько же, сколько областей', узлыТабличек.length === шайбы.length, String(узлыТабличек.length));
  let мимо = 0;
  узлыТабличек.forEach(function (у) {
    const о = Number(у.getAttribute('data-область'));
    const A = шайбы.filter(function (ш) { return ш.область === о; })[0];
    const x = Number(у.записиСтиля['--x']);
    const y = Number(у.записиСтиля['--y']);
    if (!A || Math.abs(x - A.x) > 0.5 || Math.abs(y - (A.y + 0.22 * 296 * s)) > 0.5) мимо++;
    if (!у.classList.contains('захват-табличка')) мимо++;
  });
  проверка('П18: центр каждой таблички = A + (0; 0,22·296·s) до 0,5 px', узлыТабличек.length > 0 && мимо === 0, 'не там: ' + мимо);

  // «+N»: x = A.x, низ = A.y − 208·s − 2. Берём свою область, где пилюля встаёт над фигуркой (не обрезается сверху).
  const своиОбласти = номераОбластейУ(партия, 'a');
  const подходит = своиОбласти.filter(function (о) {
    const A = шайбы.filter(function (ш) { return ш.область === о; })[0];
    return A.y - 208 * s - 2 - 18 > 0 && A.x > 40 && A.x < ШИРИНА - 40;
  });
  проверка('П18: есть своя область, где «+2» встаёт над фигуркой (ноль найденного — провал)', подходит.length > 0, 'своих ' + своиОбласти.length);
  if (подходит.length) {
    const цель = подходит[0];
    стол.поставитьВойска(цель, 2);
    const плюс = узлыКласса(слойУзел, 'захват-пилюля').filter(function (п) { return п.textContent === '+2'; })[0];
    проверка('П18: пилюля «+2» есть (ноль найденного — провал)', !!плюс);
    if (плюс) {
      const A = шайбы.filter(function (ш) { return ш.область === цель; })[0];
      const dx = Math.abs(Number(плюс.записиСтиля['--x']) - A.x);
      const dy = Math.abs(Number(плюс.записиСтиля['--y']) - (A.y - 208 * s - 2));
      проверка('П18: «+N»: середина на A.x, низ на A.y − 208·s − 2 до 0,5 px', dx <= 0.5 && dy <= 0.5, 'dx ' + dx.toFixed(2) + ', dy ' + dy.toFixed(2));
    }
  }

  // Подписи: рамка подписи не пересекает ни одну рамку «фигура + табличка» (все области Острова 320).
  const рамка = function (л, в, п, н) { return { left: л, right: п, top: в, bottom: н, width: п - л, height: н - в }; };
  const рамкиОбластей = function () {
    const итог = [];
    раскладка.таблички.forEach(function (т) { итог.push(рамка(т.x - 15, т.y - 9, т.x + 15, т.y + 9)); });
    раскладка.рамкиФигур.forEach(function (р) { итог.push(рамка(р.x, р.y, р.x + р.ширина, р.y + р.высота)); });
    return итог;
  };
  const прежняя = Узел.prototype.getBoundingClientRect;
  Узел.prototype.getBoundingClientRect = function () {
    if (this === окно) return рамка(0, 0, ШИРИНА, 800);
    const x = Number(this.записиСтиля['--x']);
    const y = Number(this.записиСтиля['--y']);
    if (this.классы().indexOf('захват-шайба') !== -1) return рамка(x - 15, y - 9, x + 15, y + 9);
    if (this.классы().indexOf('захват-пилюля--подпись') !== -1) {
      return this.классы().indexOf('захват-пилюля--под') !== -1 ? рамка(x - 30, y, x + 30, y + 18) : рамка(x - 30, y - 18, x + 30, y);
    }
    return рамка(0, 0, 0, 0);
  };
  try {
    const пересекает = function (р, ч) { return р.left < ч.right && р.right > ч.left && р.top < ч.bottom && р.bottom > ч.top; };
    let проверено = 0;
    const налегли = [];
    шайбы.forEach(function (ш) {
      стол.показатьПодписи([{ область: ш.область, текст: 'Площадь' }]);
      const п = узлыКласса(слойУзел, 'захват-пилюля--подпись')[0];
      if (!п) return;
      проверено++;
      const р = п.getBoundingClientRect();
      if (рамкиОбластей().some(function (о) { return пересекает(р, о); })) налегли.push(ш.область);
    });
    проверка('П18: подписи проверены по всем областям Острова (ноль найденного — провал)', проверено === шайбы.length, проверено + ' из ' + шайбы.length);
    проверка('П18: подпись не пересекает ни одну рамку «фигура + табличка» на Острове ' + ШИРИНА, налегли.length === 0, 'налегли у областей: ' + налегли.join(','));
  } finally {
    Узел.prototype.getBoundingClientRect = прежняя;
  }
  const итог = с.счёт();
  console.log('Итого проверок: ' + (итог.пройдено + итог.провалы.length) + ', провалов: ' + итог.провалы.length);
  return итог.провалы.length ? 1 : 0;
}

function сломать() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-таблички-'));
  const стол = fs.readFileSync(path.join(КОРЕНЬ, 'игры', 'захват', 'захват-стол.js'), 'utf8');
  const порчи = [
    ['подписи ставятся без учёта рамок (раньше срока выходим)', 'if (!фигура || !место) return;', 'return;'],
    ['зазор над фигуркой 6 вместо 2', 'const ЗАЗОР_НАД_ФИГУРКОЙ = 2;', 'const ЗАЗОР_НАД_ФИГУРКОЙ = 6;'],
    ['«+N» стоит у таблички, а не над фигуркой', 'надY: р.y - ЗАЗОР_НАД_ФИГУРКОЙ,', 'надY: т.y - 9,'],
    ['табличка сдвинута: сдвиг 0,22 стал 0,3 (порча в захват-карта-вид.js)', 'табличкаСдвиг: 0.22,', 'табличкаСдвиг: 0.3,', 'вид']
  ];
  let красных = 0;
  порчи.forEach(function (п, н) {
    const вВиде = п[3] === 'вид';
    const исходник = вВиде ? fs.readFileSync(path.join(КОРЕНЬ, 'игры', 'захват', 'захват-карта-вид.js'), 'utf8') : стол;
    if (исходник.split(п[1]).length !== 2) { console.log('ПРОВАЛ — место порчи не найдено ровно один раз: ' + п[0]); return; }
    const путь = path.join(папка, 'п' + н + '.js');
    const путьВида = path.join(папка, 'вид' + н + '.js');
    if (вВиде) fs.writeFileSync(путьВида, исходник.replace(п[1], () => п[2])
      .replace(/require\('\.\/(захват-[^']+)'\)/g, (_, имя) => 'require(' + JSON.stringify(require('./пути-проекта.js').путь(имя, КОРЕНЬ)) + ')'));
    // Порченый стол берёт настоящие соседние файлы по полному пути (а при порче вида — порченый вид).
    const порченое = стол.replace(вВиде ? '' : п[1], () => вВиде ? '' : п[2])
      .replace(/require\('\.\/(захват-[^']+)'\)/g, (_, имя) => 'require(' + JSON.stringify(вВиде && имя === 'захват-карта-вид.js' ? путьВида : require('./пути-проекта.js').путь(имя, КОРЕНЬ)) + ')');
    fs.writeFileSync(путь, порченое);
    const р = spawnSync(process.execPath, [__filename, '--файл', путь], { encoding: 'utf8' });
    const красная = р.status === 1 && /ПРОВАЛ/.test(р.stdout);
    if (красная) красных++;
    console.log((красная ? 'КРАСНЕЕТ' : 'НЕ КРАСНЕЕТ (плохо)') + ' — ' + п[0] + ' (код ' + р.status + ')');
  });
  const чист = spawnSync(process.execPath, [__filename], { encoding: 'utf8' });
  console.log('Обычный прогон: код ' + чист.status + ' — ' + чист.stdout.trim().split('\n').pop());
  console.log('Красных: ' + красных + ' из ' + порчи.length);
  process.exit(красных === порчи.length && чист.status === 0 ? 0 : 1);
}
