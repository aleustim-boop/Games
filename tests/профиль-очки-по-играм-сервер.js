'use strict';

/* =====================================================================
   ПРОФИЛЬ ПО СЕТИ: поле «поИграм» в ответе двери POST /рейтинг.

   Что проверяем. server/сервер.js, функция таблицаРейтинга — новое поле
   ответа «поИграм»: при запросе «все игры» ({игра:'все'}) отдаёт то же,
   что server/рейтинг.js моиОчкиПоИграм(номер) для спрашивающего игрока;
   при запросе одной игры — честный null; игрок, которого не удалось
   опознать по подписи Telegram, поля вовсе не получает (ответ короче,
   с причиной словами — таблицаРейтинга отвечает так ещё до сборки поля).

   В отличие от tests/профиль-очки-по-играм.js (проверяет самою функцию
   рейтинга напрямую), здесь настоящий сервер поднят на порту и говорит
   HTTP — так же, как с ним говорит браузер игрока.

   Сценарии:
     а) «Все игры» от узнанного игрока — поИграм: массив с верными
        числами (сверка с рейтинг.моиОчкиПоИграм напрямую) и в порядке
        по убыванию очков, который НЕ совпадает с порядком, в котором
        игры засевались (иначе снятая сортировка прошла бы незамеченной).
     б) Одна игра («дурак») от того же игрока — поИграм === null.
     в) «Все игры» без подписи Telegram — игрок не опознан, дверь
        отвечает отказом словами ещё до сборки поля: поИграм в ответе
        нет вовсе (undefined) — для клиента это то же самое, что null.
     г) «Все игры» от узнанного игрока без единой партии — поИграм —
        пустой МАССИВ, не null (эту разницу должен передать и сервер).

   Данные засеваются напрямую через рейтинг.учестьПартию (тот же приём,
   что в tests/профиль-очки-по-играм.js и tests/рейтинг-все-игры-сервер.js):
   партий через комнаты никто не играет, поэтому server/комнаты.js этот
   файл не трогает и не открывает.

   ЛОМАЮЩИЙ ЗАПУСК (--сломать). Настоящий server/сервер.js не портится:
   делаем его КОПИЮ во временной папке, где поИграм всегда null (как в
   задании — «например, всегда null»), поднимаем копию на ВТОРОМ порту
   и гоняем по ней сценарии (а) и (г) — оба ждут массив, получают null,
   проверка обязана покраснеть. Копия требует и починки require: сама
   лежит во временной папке, а её require('./комнаты.js') и соседей
   без абсолютных путей там не найдёт; правим ровно эти строки и путь
   к bot/.env (иначе копия не узнает токен бота и не проверит подпись
   ни одного игрока). Каждая замена обязана найтись ровно один раз —
   иначе выходим кодом 2: значит сервер перестроили, и поломку пора
   чинить тем же коммитом, а не верить старой.

   «process.pid» в именах временных папок — тот же приём, что в
   tests/рейтинг-все-игры-сервер.js: обе HTTP-копии (обычная и ломаная)
   живут в ЭТОМ ЖЕ процессе на разных портах и гасятся через http.Server
   .close(), отдельного процесса под node здесь не заводим — сервер
   в этом проекте всегда так и подключают проверки (см. хотя бы
   tests/проверка-статистики.js).

   Запуск:
       node tests/профиль-очки-по-играм-сервер.js
       node tests/профиль-очки-по-играм-сервер.js --сломать

   Выход: 0 — всё хорошо; 1 — есть провалы; 2 — поломку не удалось
   применить ровно один раз, или в системе не настроен токен бота.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const crypto = require('crypto');

const ЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;
const КОРЕНЬ = path.join(__dirname, '..');
const ФАЙЛ_СЕРВЕРА = path.join(КОРЕНЬ, 'server', 'сервер.js');
const ФАЙЛ_РЕЙТИНГА = path.join(КОРЕНЬ, 'server', 'рейтинг.js');
const ФАЙЛ_ТОКЕНА = path.join(КОРЕНЬ, 'bot', '.env');

/* Данные уводим в свою временную папку ДО подключения сервера — иначе
   первое же чтение подхватило бы боевые файлы владельца. Имя с
   process.pid — чтобы два прогона этой проверки подряд не столкнулись
   временными папками. */
const СВОЯ_ПАПКА = path.join(os.tmpdir(), 'профиль-очки-по-играм-сервер-' + process.pid);
fs.mkdirSync(СВОЯ_ПАПКА, { recursive: true });
process.env.GAMES_DATA = СВОЯ_ПАПКА;

const ПОРТ = 8801;          // обычный сервер этой проверки
const ПОРТ_КОПИИ = 8802;    // ломаная копия — второй порт, не пересекается

const сервер = require(ФАЙЛ_СЕРВЕРА);
const рейтинг = require(ФАЙЛ_РЕЙТИНГА);

const ТОКЕН = (сервер.прочитатьНастройки().BOT_TOKEN || '').trim();
if (!ТОКЕН) {
  console.log('НЕТ ТОКЕНА — bot/.env не настроен, подпись initData проверить нечем. Проверка не пойдёт.');
  process.exit(2);
}

/* Подпись initData тем же приёмом, что и tests/проверка-статистики.js:
   настоящий HMAC настоящим токеном бота — сервер эту подпись примет
   как подлинную. */
function подписать(кто) {
  const поля = new URLSearchParams();
  поля.set('user', JSON.stringify(кто));
  поля.set('auth_date', String(Math.floor(Date.now() / 1000)));
  const строки = [];
  for (const пара of поля) строки.push(пара[0] + '=' + пара[1]);
  строки.sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(ТОКЕН).digest();
  поля.set('hash', crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex'));
  return поля.toString();
}

function стук(порт, тело) {
  return fetch('http://127.0.0.1:' + порт + '/рейтинг', {
    method: 'POST', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(тело || {})
  }).then(function (о) { return о.json(); });
}

function закрыть(httpСервер) {
  return new Promise(function (готово) {
    if (!httpСервер) return готово();
    /* Небольшая пауза после close(): на Windows node ловит нативный сбой
       (Assertion failed ... UV_HANDLE_CLOSING), если process.exit() зовут
       вплотную к колбэку close — внутреннее закрытие хэндла ещё не
       успевает доиграть. Проверено отдельным прогоном без паузы. */
    httpСервер.close(function () { setTimeout(готово, 100); });
  });
}

/* =====================================================================
   Кто играет в этой проверке
   ===================================================================== */

const ИГРОК_ВСЕ = 940001;        // играет в дурака и шашки — сверяем сумму/порядок
const ИГРОК_ОДНА_ИГРА = 940002;  // играет только в дурака
const ИГРОК_БЕЗ_ПАРТИЙ = 940003; // узнан, но ни одной партии
const ПЕРВЫЙ_СОПЕРНИК = 950001;

/* Дурак засевается ПЕРВЫМ (меньше очков), шашки — ВТОРЫМ (больше очков):
   порядок в памяти таблиц («дурак» раньше «шашки») нарочно расходится
   с ожидаемым порядком ответа («шашки» раньше «дурак») — если сортировку
   в ответе снимут, эта проверка не пропустит поломку незамеченной. */
function засеять() {
  рейтинг.забытьВсё();
  рейтинг.включитьЗапись();

  let следующийСоперник = ПЕРВЫЙ_СОПЕРНИК;
  function победа(игра, номер) {
    рейтинг.учестьПартию(игра, [
      { номер: номер, имя: 'Тестовик', этоБот: false, победил: true, ничья: false },
      { номер: следующийСоперник++, имя: 'Соперник', этоБот: false, победил: false, ничья: false }
    ]);
  }

  победа('дурак', ИГРОК_ВСЕ);                 // 1 победа = 10 очков
  for (let р = 0; р < 3; р++) победа('шашки', ИГРОК_ВСЕ);  // 3 победы = 30 очков
  for (let р = 0; р < 2; р++) победа('дурак', ИГРОК_ОДНА_ИГРА); // 2 победы = 20 очков
  // ИГРОК_БЕЗ_ПАРТИЙ нарочно не засевается — его в таблицах нет вовсе.
}

/* =====================================================================
   Копилка проверок
   ===================================================================== */

function создатьКопилку(молча) {
  return { проверок: 0, провалы: [], молча: молча === true };
}
function проверить(копилка, условие, что) {
  копилка.проверок++;
  if (!условие) {
    копилка.провалы.push(что);
    if (!копилка.молча) console.log('  ✗ ' + что);
  } else if (!копилка.молча) {
    console.log('  ✓ ' + что);
  }
}

/* =====================================================================
   Сценарии — гоняются и по настоящему серверу, и по ломаной копии
   ===================================================================== */

async function сценарии(порт, копилка) {
  /* а) «Все игры», узнанный игрок — поИграм: массив, верный порядок и числа. */
  const ожидаемое = рейтинг.моиОчкиПоИграм(ИГРОК_ВСЕ);
  const а = await стук(порт, { игра: 'все', initData: подписать({ id: ИГРОК_ВСЕ, first_name: 'Игрок' }) });

  проверить(копилка, а && а.ок === true, 'а) ок: true');
  проверить(копилка, Array.isArray(а.поИграм), 'а) поИграм — массив, получили: ' + JSON.stringify(а && а.поИграм));
  if (Array.isArray(а.поИграм)) {
    проверить(копилка, JSON.stringify(а.поИграм) === JSON.stringify(ожидаемое),
      'а) поИграм совпадает с рейтинг.моиОчкиПоИграм: ожидали ' +
      JSON.stringify(ожидаемое) + ', получили ' + JSON.stringify(а.поИграм));
    проверить(копилка, а.поИграм.length === 2, 'а) две записи (дурак и шашки)');
    проверить(копилка, а.поИграм.map(function (з) { return з.игра; }).join(',') === 'шашки,дурак',
      'а) порядок по убыванию очков: шашки → дурак, получили ' +
      а.поИграм.map(function (з) { return з.игра; }).join(' → '));
    const шашки = а.поИграм.find(function (з) { return з.игра === 'шашки'; });
    проверить(копилка, !!шашки && шашки.очки === 30 && шашки.побед === 3 && шашки.партий === 3,
      'а) шашки: 30 очков, 3 победы, 3 партии — получили ' + JSON.stringify(шашки));
    const дурак = а.поИграм.find(function (з) { return з.игра === 'дурак'; });
    проверить(копилка, !!дурак && дурак.очки === 10 && дурак.побед === 1 && дурак.партий === 1,
      'а) дурак: 10 очков, 1 победа, 1 партия — получили ' + JSON.stringify(дурак));
    /* Номера наружу не уходят — ни свой, ни соперников. */
    const какТекст = JSON.stringify(а.поИграм);
    проверить(копилка, какТекст.indexOf(String(ИГРОК_ВСЕ)) === -1,
      'а) свой номер не встречается в поИграм');
  }

  /* б) Одна игра — поИграм строго null. */
  const б = await стук(порт, { игра: 'дурак', initData: подписать({ id: ИГРОК_ВСЕ, first_name: 'Игрок' }) });
  проверить(копилка, б && б.ок === true, 'б) ок: true');
  проверить(копилка, б.поИграм === null,
    'б) запрос одной игры даёт поИграм === null, получили: ' + JSON.stringify(б && б.поИграм));

  /* в) Неузнанный игрок (нет initData) — поля поИграм в ответе вовсе нет. */
  const в = await стук(порт, { игра: 'все' });
  проверить(копилка, в && в.ок === false && в.узналиВас === false,
    'в) неузнанного отклоняют словами: ок:false, узналиВас:false');
  проверить(копилка, в.поИграм === undefined || в.поИграм === null,
    'в) поля поИграм нет (undefined) либо null, получили: ' + JSON.stringify(в ? в.поИграм : в));

  /* г) Узнанный игрок без единой партии — поИграм: пустой массив, не null. */
  const г = await стук(порт, { игра: 'все', initData: подписать({ id: ИГРОК_БЕЗ_ПАРТИЙ, first_name: 'Пустой' }) });
  проверить(копилка, г && г.ок === true, 'г) ок: true (игрок узнан)');
  проверить(копилка, Array.isArray(г.поИграм) && г.поИграм.length === 0,
    'г) поИграм — пустой массив, не null: ' + JSON.stringify(г && г.поИграм));
  проверить(копилка, г.поИграм !== null, 'г) поИграм !== null (отличаем «нет партий» от «нет поля»)');
}

/* =====================================================================
   Обычный прогон — настоящий server/сервер.js
   ===================================================================== */

async function прогнатьСОригиналом() {
  console.log('=== Профиль по сети: поИграм (настоящий server/сервер.js, порт ' + ПОРТ + ') ===');
  const копилка = создатьКопилку(false);
  let httpСервер = null;
  try {
    засеять();
    httpСервер = сервер.запустить(ПОРТ, 2000);
    await сценарии(ПОРТ, копилка);
  } catch (беда) {
    копилка.провалы.push('проверка оборвалась: ' + беда.message);
    console.log('ПРОВЕРКА ОБОРВАЛАСЬ: ' + беда.message);
    console.log(беда.stack);
  } finally {
    await закрыть(httpСервер);
  }
  return копилка;
}

/* =====================================================================
   Ломающий запуск: копия server/сервер.js с сорванным поИграм
   ===================================================================== */

const ОТНОСИТЕЛЬНЫЕ_ТРЕБОВАНИЯ = [
  'комнаты.js', 'подбор.js', 'шлагбаум.js', 'знакомые.js', 'друзья.js',
  'не-звать.js', 'статистика.js', 'папка-данных.js', 'копии-данных.js',
  'рейтинг.js', 'раздача-дня.js', 'билеты.js', 'лента.js',
  'игры/умолчания.js', 'игры/реестр.js'
];

function заменитьРовноОдин(текст, старое, новое, имя) {
  const сколько = текст.split(старое).length - 1;
  if (сколько !== 1) {
    console.log('ПОЛОМКА НЕ ПРИМЕНИЛАСЬ («' + имя + '»): строка найдена ' + сколько +
      ' раз(а) вместо одного. Похоже, server/сервер.js перестроили — поправьте проверку тем же коммитом.');
    process.exit(2);
  }
  return текст.split(старое).join(новое);
}

function собратьКопию() {
  const папкаКопии = path.join(os.tmpdir(), 'профиль-очки-по-играм-копия-' + process.pid);
  fs.mkdirSync(папкаКопии, { recursive: true });

  let текст = fs.readFileSync(ФАЙЛ_СЕРВЕРА, 'utf8');

  /* Сама поломка: поИграм всегда null, будто «все игры» никогда не
     запрашивались — ровно так, как описано в задании. */
  текст = заменитьРовноОдин(текст,
    '  const поИграм = этоВсеИгры ? рейтинг.моиОчкиПоИграм(кто) : null;',
    '  const поИграм = null;',
    'поИграм всегда null');

  /* Копия лежит во временной папке — её require('./комнаты.js') и соседей
     без абсолютных путей не найдёт. Соседние файлы сами не копируются и
     остаются на месте, поэтому их СОБСТВЕННЫЕ require друг на друга не
     ломаются — правим только то, что requir'ит сама эта копия. */
  for (const имя of ОТНОСИТЕЛЬНЫЕ_ТРЕБОВАНИЯ) {
    const абсолютный = path.join(КОРЕНЬ, 'server', имя).split(path.sep).join('/');
    текст = заменитьРовноОдин(текст,
      "require('./" + имя + "')",
      "require('" + абсолютный + "')",
      'require ' + имя);
  }

  /* Токен бота копия тоже читает сама (по __dirname, который во временной
     папке ведёт в никуда) — без починки подпись initData никто бы не
     подтвердила, и ломающий прогон молчал бы не о том. */
  const путьТокена = ФАЙЛ_ТОКЕНА.split(path.sep).join('/');
  текст = заменитьРовноОдин(текст,
    "const ТОКЕН_БОТА = (прочитатьНастройки().BOT_TOKEN || '').trim();",
    "const ТОКЕН_БОТА = (прочитатьНастройки('" + путьТокена + "').BOT_TOKEN || '').trim();",
    'путь к bot/.env');

  const файлКопии = path.join(папкаКопии, 'сервер.js');
  fs.writeFileSync(файлКопии, текст, 'utf8');
  return { папка: папкаКопии, файл: файлКопии };
}

async function прогнатьСКопией(общая) {
  console.log('\n=== Профиль по сети: поИграм (КОПИЯ с поломкой, порт ' + ПОРТ_КОПИИ + ') ===');

  const копия = собратьКопию();
  const копилка = создатьКопилку(true);
  let httpСервер = null;
  try {
    /* server/рейтинг.js копия сервера подключит по абсолютному пути —
       тот же файл, что уже загружен настоящим сервером, значит данные,
       засеянные выше, для копии уже на месте, засевать заново не нужно. */
    const серверКопии = require(копия.файл);
    httpСервер = серверКопии.запустить(ПОРТ_КОПИИ, 2000);
    await сценарии(ПОРТ_КОПИИ, копилка);
  } catch (беда) {
    копилка.провалы.push('копия упала: ' + беда.message);
  } finally {
    await закрыть(httpСервер);
    delete require.cache[копия.файл];
    try { fs.rmSync(копия.папка, { recursive: true, force: true }); } catch (е) { /* нарочно молчим */ }
  }

  console.log('Ломаная копия: покраснело проверок ' + копилка.провалы.length + ' из ' + копилка.проверок);
  for (const беда of копилка.провалы.slice(0, 5)) console.log('  ✗ ' + беда);

  проверить(общая, копилка.провалы.length > 0, 'ломаная копия замечена проверкой');
}

/* =====================================================================
   Главный запуск
   ===================================================================== */

(async function () {
  const общая = await прогнатьСОригиналом();

  if (ЛОМАТЬ) {
    await прогнатьСКопией(общая);
  }

  try { fs.rmSync(СВОЯ_ПАПКА, { recursive: true, force: true }); } catch (е) { /* нарочно молчим */ }

  console.log('\n----------------------------------------');
  for (const беда of общая.провалы) console.log('  - ' + беда);
  console.log('Итого проверок: ' + общая.проверок + ', провалов: ' + общая.провалы.length);
  process.exit(общая.провалы.length > 0 ? 1 : 0);
})();
