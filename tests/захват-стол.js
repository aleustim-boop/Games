// Поддельные часы: время и таймер долгого касания крутит сама проверка.
function сделатьЧасы() {
  const ч = { t: 1000, задачи: [], следующий: 1 };
  ч.время = function () { return ч.t; };
  ч.таймер = {
    поставить(действие, мс) {
      const номер = ч.следующий++;
      ч.задачи.push({ номер: номер, действие: действие, при: ч.t + мс });
      return номер;
    },
    снять(номер) { ч.задачи = ч.задачи.filter(function (з) { return з.номер !== номер; }); }
  };
  ч.пройти = function (мс) {
    ч.t += мс;
    const готовые = ч.задачи.filter(function (з) { return з.при <= ч.t; });
    ч.задачи = ч.задачи.filter(function (з) { return з.при > ч.t; });
    готовые.forEach(function (з) { з.действие(); });
  };
  return ч;
}

