  партия.хозяева[пары.удар.в] = null;
  стол.открытьПриказ(пары.удар.из, пары.удар.в);
  проверка('у ничьей области строки про подкрепление нет', узел('захват-приказ-подкрепление').classList.contains('скрыт'));
  стол.закрытьПриказ();
