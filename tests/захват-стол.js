// ---------- прижим пилюль-подписей к краям карты ----------

function проверитьПрижимПилюль() {
  const партия = сделатьПартию();
  const документ = сделатьДокумент();
  const стол = ЗахватСтол.создать({ документ: документ, рисункиЕсть: false, слушатели: {} });
  стол.начатьРаунд(партия, 'a', { имена: { a: 'Вы' } });
  const раскладка = стол.показатьСлой(ШИРИНА_КАРТЫ);
  const слой = документ.getElementById('захват-слой');
  const ширинаКарты = КартаВид.геометрия(Правила.картаПартии(партия), ШИРИНА_КАРТЫ).ширина;
  const шайбы = раскладка.шайбы.slice().sort(function (а, б) { return а.x - б.x; });
  проверка('прижим: шайбы на карте есть (ноль найденного — провал)', шайбы.length >= 3, 'шайб ' + шайбы.length);
  const слева = шайбы[0];
  const справа = шайбы[шайбы.length - 1];
  // Пилюля шире двух расстояний до краёв — гарантированно вылезла бы у обеих крайних шайб.
  const ширина = 2 * Math.max(слева.x, ширинаКарты - справа.x) + 20;
  const середина = шайбы.filter(function (ш) { return ш.x - ширина / 2 >= 0 && ш.x + ширина / 2 <= ширинаКарты; })[0];
  проверка('прижим: есть шайба, где пилюля влезает целиком (ноль найденного — провал)', !!середина,
    'ширина пилюли ' + ширина + ', карта ' + ширинаКарты);
  if (!середина) return;

  function иксПодписи(шайба) {
    стол.показатьПодписи([{ область: шайба.область, текст: 'Подпись' }]);
    const п = узлыКласса(слой, 'захват-пилюля--подпись').filter(function (у) {
      return у.getAttribute('data-область') === String(шайба.область);
    })[0];
    return п ? Number(п.записиСтиля['--x']) : null;
  }

  ширинаПилюлиВПроверке = ширина;
  const л = иксПодписи(слева);
  const п = иксПодписи(справа);
  const ц = иксПодписи(середина);
  ширинаПилюлиВПроверке = 0;
  const без = иксПодписи(слева);
  стол.снятьПодписи();

  const допуск = 0.01;
  проверка('прижим: пилюля у левого края — внутри карты (левый край ≥ 0)', л !== null && л - ширина / 2 >= -допуск,
    'x ' + л + ', ширина ' + ширина);
  проверка('прижим: пилюля у правого края — внутри карты (правый край ≤ ширины карты)', п !== null && п + ширина / 2 <= ширинаКарты + допуск,
    'x ' + п + ', ширина ' + ширина + ', карта ' + ширинаКарты);
  проверка('прижим: пилюля в середине — ровно по центру шайбы', ц !== null && Math.abs(ц - середина.x) < допуск,
    'x ' + ц + ', шайба ' + середина.x);
  проверка('прижим: без замера ширины пилюля по центру шайбы, без падения', без !== null && Math.abs(без - слева.x) < допуск,
    'x ' + без + ', шайба ' + слева.x);
}

