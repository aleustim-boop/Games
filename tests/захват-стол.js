// Лист удара на свежем столе: у «из» 4 войска (можно послать 3), в цели — защитников столько, сколько дали.
function листУдараНа(защитников) {
  const партия = сделатьПартию();
  const пара = найтиПары(партия).удар;
  партия.войска[пара.из] = 4;
  партия.войска[пара.в] = защитников;
  const документ = сделатьДокумент();
  const стол = ЗахватСтол.создать({ документ: документ, рисункиЕсть: false, слушатели: {} });
  стол.начатьРаунд(партия, 'a', { имена: { a: 'Вы' } });
  const открыт = стол.открытьПриказ(пара.из, пара.в);
  проверка('Д-6б: лист слабого удара открывается (ноль найденного — провал)', открыт.принято === true, открыт.причина);
  const у = function (id) { return документ.getElementById(id); };
  return {
    стол: стол,
    партия: партия,
    пара: пара,
    строка: function () { return у('захват-приказ-подкрепление'); },
    кнопка: function () { return у('захват-приказ-отдать'); }
  };
}

function проверитьЛистСлабогоУдара() {
  // 3 против 5: взять нельзя.
  const нуль = листУдараНа(5);
  проверка('Д-6б: при 0 % строка «Взять нельзя: защитников 5, вы шлёте 3 — удар только ослабит их»',
    !нуль.строка().classList.contains('скрыт') &&
    нуль.строка().textContent === 'Взять нельзя: защитников 5, вы шлёте 3 — удар только ослабит их', нуль.строка().textContent);
  проверка('Д-6б: при 0 % кнопка «Ударить всё равно»', нуль.кнопка().textContent === 'Ударить всё равно', нуль.кнопка().textContent);
  проверка('Д-6б: при 0 % кнопка не главная (тёмная)', !нуль.кнопка().classList.contains('кнопка--главная'));
  проверка('Д-6б: при 0 % кнопка не выключена', нуль.кнопка().getAttribute('disabled') === null);
  const удар = нуль.стол.отдатьПриказ();
  проверка('Д-6б: при 0 % удар всё равно отдаётся', удар.принято === true && нуль.стол.черновик().приказы.length === 1, удар.причина);

  // 3 против 3: шанс есть, но мал.
  const малый = листУдараНа(3);
  const процент = Правила.процентШанса(3, 3).процент;
  проверка('Д-6б: для проверки 3 против 3 — шанс от 1 до 29 % (ноль найденного — провал)', процент >= 1 && процент < 30, 'шанс ' + процент);
  проверка('Д-6б: малый шанс — строка «Шанс мал — удар, скорее всего, отобьют»',
    !малый.строка().classList.contains('скрыт') && малый.строка().textContent === 'Шанс мал — удар, скорее всего, отобьют',
    малый.строка().textContent);
  проверка('Д-6б: малый шанс — кнопка «Ударить», главная',
    малый.кнопка().textContent === 'Ударить' && малый.кнопка().classList.contains('кнопка--главная'), малый.кнопка().textContent);

  // Ползунок двигают — строка и кнопка пересчитываются.
  малый.стол.задатьЧисло(2);
  проверка('Д-6б: ползунок на 2 против 3 — снова «Взять нельзя…», кнопка «Ударить всё равно»',
    /^Взять нельзя: защитников 3, вы шлёте 2/.test(малый.строка().textContent) && малый.кнопка().textContent === 'Ударить всё равно',
    малый.строка().textContent);
  малый.стол.задатьЧисло(3);
  проверка('Д-6б: ползунок обратно на 3 — «Шанс мал…» и главная «Ударить»',
    /^Шанс мал/.test(малый.строка().textContent) && малый.кнопка().textContent === 'Ударить' &&
    малый.кнопка().classList.contains('кнопка--главная'));

  // Сильный удар (1 защитник): ни предупреждения, ни тёмной кнопки.
  const сильный = листУдараНа(1);
  проверка('Д-6б: сильный удар — без предупреждения, «Ударить» главная',
    !/Взять нельзя|Шанс мал/.test(сильный.строка().textContent) && сильный.кнопка().textContent === 'Ударить' &&
    сильный.кнопка().classList.contains('кнопка--главная'), сильный.строка().textContent);

  // После слабого удара лист перевода снова с главной кнопкой «Перевести».
  const после = листУдараНа(5);
  const перевод = найтиПары(после.партия).перевод;
  проверка('Д-6б: есть пара для перевода (ноль найденного — провал)', !!перевод);
  if (!перевод) return;
  после.партия.войска[перевод.из] = Math.max(после.партия.войска[перевод.из], 5);
  после.стол.закрытьПриказ();
  после.стол.открытьПриказ(перевод.из, перевод.в);
  проверка('Д-6б: после слабого удара лист перевода — «Перевести», главная, без предупреждения',
    после.кнопка().textContent === 'Перевести' && после.кнопка().classList.contains('кнопка--главная') &&
    !/Взять нельзя|Шанс мал/.test(после.строка().textContent), после.кнопка().textContent);
}

function ожидаемаяЦельОстатка(партия) {
  const куда = Правила.кудаОстаток(партия, 'a', { расстановка: {}, приказы: [] });
  const имя = Правила.картаПартии(партия).области[куда.область - 1].имя;
  return { область: куда.область, столица: куда.столица, имя: имя };
}

