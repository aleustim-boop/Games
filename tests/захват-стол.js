// Число из начала текста чипа: «+2 за край Кряж» → 2.
function числоЧипа(текст) {
  const найдено = /^\+(\d+) /.exec(текст);
  return найдено ? Number(найдено[1]) : NaN;
}

function суммаЧипов(тексты) {
  return тексты.map(числоЧипа).reduce(function (с, ч) { return с + ч; }, 0);
}

