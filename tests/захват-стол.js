  const готово = стол.поставитьОстатокИГотово();
  проверка('«Поставить и готово» — готов', готово.принято === true && стол.готов() === true, готово.причина);
  проверка('слушатель «приГотово» позван', получено.готово === 1);
  проверка('кнопка стала «Изменить»', узел('захват-готово').textContent === 'Изменить');
