function сделатьПервуюПартию() {
  return Правила.новаяПартия({ игроки: ['a', 'бот-1', 'бот-2'], люди: ['a'], новичок: 'a' }, function () { return 0.5; });
}

function шайбыСКлассом(документ, имяКласса) {
  return узлыКласса(документ.getElementById('захват-слой'), 'захват-шайба').filter(function (ш) { return ш.классы().indexOf(имяКласса) !== -1; });
}

// Новый стол на данной партии: отдаёт стол и функции, читающие метки из слоя шайб того же документа.
function столДляПодсказок(партия) {
  const документ = сделатьДокумент();
  const стол = ЗахватСтол.создать({ документ: документ, рисункиЕсть: false, слушатели: {} });
  стол.начатьРаунд(партия, 'a', { имена: { a: 'Вы' } });
  const раскладка = function () { return стол.показатьСлой(358); };
  раскладка();
  return {
    документ: документ,
    стол: стол,
    раскладка: раскладка,
    документСтрокаПодсказки: function () { return документ.getElementById('захват-подсказка').textContent; },
    пульс: function () { return шайбыСКлассом(документ, 'захват-шайба--пульс').map(function (ш) { return Number(ш.атрибуты['data-область']); }); },
    цель: function () { return шайбыСКлассом(документ, 'захват-шайба--цель-новичка').map(function (ш) { return Number(ш.атрибуты['data-область']); }); }
  };
}

function расставитьВсё(стол, партия) {
  const своя = номераОбластейУ(партия, 'a')[0];
  let защита = 100;
  while (партия.подкрепление.a - Object.keys(стол.черновик().расстановка).reduce(function (с, к) { return с + стол.черновик().расстановка[к]; }, 0) > 0 && защита-- > 0) {
    стол.поставитьВойска(своя, 1);
  }
  return своя;
}

function проверитьПодсказкиНовичка() {
  const партия = сделатьПервуюПартию();
  const мои = номераОбластейУ(партия, 'a');
  const соседство = Карты.соседство(Правила.картаПартии(партия));
  const н = столДляПодсказок(партия);

  // Раунд 1, войска ещё не расставлены: пульс на всех своих областях, цели ещё нет.
  проверка('раунд 1: у новичка есть свои области (ноль найденного — провал)', мои.length > 0);
  проверка('раунд 1: метка пульса на каждой своей области', н.пульс().length === мои.length &&
    мои.every(function (о) { return н.пульс().indexOf(о) !== -1; }), 'пульс на ' + JSON.stringify(н.пульс()));
  проверка('раунд 1: пока войска не расставлены, «цели новичка» нет', н.цель().length === 0);

  // Расставил подкрепление: одна цель — ничья область рядом со своей, с лучшим шансом, при равенстве меньший номер.
  расставитьВсё(н.стол, партия);
  const цели = н.цель();
  проверка('раунд 1: после расстановки ровно одна «цель новичка»', цели.length === 1, JSON.stringify(цели));
  const ничьиРядом = [];
  мои.forEach(function (из) {
    (соседство[из] || []).forEach(function (в) { if (партия.хозяева[в] === null && ничьиРядом.indexOf(в) === -1) ничьиРядом.push(в); });
  });
  проверка('есть ничьи области рядом со своими (ноль найденного — провал)', ничьиРядом.length > 0);
  проверка('цель новичка — ничья область рядом со своей', цели.length === 1 && ничьиРядом.indexOf(цели[0]) !== -1);
  const шансы = ничьиРядом.map(function (в) {
    const войск = мои.reduce(function (с, из) { return с + ((соседство[из] || []).indexOf(в) !== -1 ? Math.max(0, партия.войска[из] - 1) : 0); }, 0);
    return { область: в, шанс: Правила.шанс(войск + партия.подкрепление.a, партия.войска[в]) };
  }).sort(function (а, б) { return б.шанс - а.шанс || а.область - б.область; });
  проверка('цель новичка — с наибольшим шансом (при равенстве меньший номер)', цели[0] === шансы[0].область,
    'цель ' + цели[0] + ', ждали ' + шансы[0].область);
  const целиВРисунке = н.раскладка().слои['цели'].map(function (э) { return э.область; });
  проверка('на цель новичка кладётся готовый рисунок «цели» (слой карты)', целиВРисунке.length > 0 &&
    целиВРисунке.every(function (о) { return о === цели[0]; }), JSON.stringify(целиВРисунке));

  // «Готово» гасит метки, «Изменить» (всё ещё раунд 1) возвращает.
  н.стол.нажатьГотово();
  проверка('после «Готово» пульса и цели нет', н.пульс().length === 0 && н.цель().length === 0);
  н.стол.изменить();
  проверка('«Изменить» в раунде 1 возвращает метки', н.пульс().length === мои.length && н.цель().length === 1);

  // Раунд 2 той же первой партии: меток нет.
  партия.раунд = 2;
  н.стол.начатьРаунд(партия, 'a', { имена: { a: 'Вы' } });
  н.раскладка();
  проверка('раунд 2: пульса нет', н.пульс().length === 0);
  проверка('раунд 2: цели новичка нет', н.цель().length === 0);

  // Вторая партия (не первая): меток нет и в раунде 1.
  const вторая = сделатьПартию();
  const в2 = столДляПодсказок(вторая);
  расставитьВсё(в2.стол, вторая);
  проверка('вторая партия: пульса нет', в2.пульс().length === 0);
  проверка('вторая партия: цели новичка нет', в2.цель().length === 0);
}

// ---------- Д-8а: шайба показывает «останется дома», пунктир гаснет после удара (разбор Г3е, решения 1 и 2) ----------

function проверитьШайбуГ3е() {
  const партия = сделатьПервуюПартию();
  const пары = найтиПары(партия);
  проверка('Д-8а: есть пара «моя → чужая» (ноль найденного — провал)', !!пары.удар);
  if (!пары.удар) return;
  const из = пары.удар.из;
  const в = пары.удар.в;
  // Как на снимке г3е-05: в области 2 войска, подкрепление 5, всё поставлено в неё, удар на 6.
  партия.войска[из] = 2;
  партия.подкрепление.a = 5;
  const н = столДляПодсказок(партия);
  const текстШайбы = function () {
    const ш = узлыКласса(узел_слоя(н), 'захват-шайба').filter(function (х) { return Number(х.getAttribute('data-область')) === из; })[0];
    return ш ? узлыКласса(ш, 'захват-шайба__число')[0].textContent : null;
  };
  const плюсы = function () {
    return узлыКласса(узел_слоя(н), 'захват-пилюля').filter(function (п) { return Number(п.getAttribute('data-область')) === из; })
      .map(function (п) { return п.textContent; });
  };
  const листЧисло = function () { return н.документ.getElementById('захват-приказ-число').textContent; };
  н.стол.поставитьВойска(из, 5);
  н.раскладка();
  проверка('Д-8а: до приказа шайба «7» и метка «+5»', текстШайбы() === '7' && плюсы().indexOf('+5') !== -1,
    'шайба ' + текстШайбы() + ', метки ' + плюсы().join(','));
  const открыт = н.стол.открытьПриказ(из, в);
  проверка('Д-8а: лист приказа открылся (ноль найденного — провал)', открыт.принято === true, открыт.причина);
  // Д-10б (реш. 6): «из N» — войска в области (2 + 5 поставлено = 7), а не потолок ползунка.
  проверка('Д-8а: лист «Отправить: 6 из 7 · останется 1»', листЧисло() === 'Отправить: 6 из 7 · останется 1', листЧисло());
  н.стол.задатьЧисло(4);
  проверка('Д-8а: ползунок на 4 — «Отправить: 4 из 7 · останется 3»', листЧисло() === 'Отправить: 4 из 7 · останется 3', листЧисло());
  н.стол.задатьЧисло(6);
  const итог = н.стол.отдатьПриказ();
  проверка('Д-8а: удар 6 отдан (ноль найденного — провал)', итог.принято === true && н.стол.черновик().приказы.length === 1, итог.причина);
  н.раскладка();
  проверка('Д-8а: после удара 6 из 6 на шайбе «1»', текстШайбы() === '1', 'шайба ' + текстШайбы());
  проверка('Д-8а: после удара метки «+5» у этой области нет', плюсы().length === 0, 'метки ' + плюсы().join(','));
  проверка('Д-8а: с ударом в черновике цель новичка = null', н.стол.цельНовичка() === null);
  проверка('Д-8а: с ударом в черновике класса «цель-новичка» нет ни на одной шайбе', н.цель().length === 0, JSON.stringify(н.цель()));
  // Приказ убрали — всё возвращается.
  н.стол.открытьПриказ(из, в);
  const убран = н.стол.убратьПриказ();
  проверка('Д-8а: приказ убран (ноль найденного — провал)', убран.принято === true && н.стол.черновик().приказы.length === 0, убран.причина);
  н.раскладка();
  проверка('Д-8а: приказ убрали — шайба снова «7» и метка «+5» вернулась', текстШайбы() === '7' && плюсы().indexOf('+5') !== -1,
    'шайба ' + текстШайбы() + ', метки ' + плюсы().join(','));
  const цель = н.стол.цельНовичка();
  проверка('Д-8а: без удара цель новичка есть: { область, безХозяина }', !!цель && typeof цель.область === 'number' && typeof цель.безХозяина === 'boolean',
    JSON.stringify(цель));
  проверка('Д-8а: без удара пунктир на шайбе цели', н.цель().length === 1 && !!цель && н.цель()[0] === цель.область, JSON.stringify(н.цель()));
  проверка('Д-8а: безХозяина совпадает с хозяином цели', !!цель && цель.безХозяина === (партия.хозяева[цель.область] === null));

  // Перевод в свою область не гасит пунктир (в счёт идут только удары).
  const партия2 = сделатьПервуюПартию();
  const пары2 = найтиПары(партия2);
  проверка('Д-8а: есть пара «моя → моя» для перевода (ноль найденного — провал)', !!пары2.перевод);
  if (!пары2.перевод) return;
  партия2.войска[пары2.перевод.из] = 4;
  const н2 = столДляПодсказок(партия2);
  расставитьВсё(н2.стол, партия2);
  н2.раскладка();
  const до = н2.цель().length;
  const о2 = н2.стол.открытьПриказ(пары2.перевод.из, пары2.перевод.в);
  const о2итог = о2.принято ? н2.стол.отдатьПриказ() : о2;
  н2.раскладка();
  проверка('Д-8а: перевод отдан и пунктир до него был (ноль найденного — провал)', о2итог.принято === true && до === 1, о2итог.причина + ' / до ' + до);
  проверка('Д-8а: после перевода (не удара) пунктир остаётся', н2.стол.цельНовичка() !== null && н2.цель().length === 1,
    JSON.stringify(н2.цель()));
}

