  партия.войска[пары.перевод.из] = Math.max(партия.войска[пары.перевод.из], 5);
  const переводОткрыт = стол.открытьПриказ(пары.перевод.из, пары.перевод.в);
  проверка('лист перевода открывается', переводОткрыт.принято === true, переводОткрыт.причина);
  проверка('у перевода шанса и потерь нет', узел('захват-приказ-шанс').classList.contains('скрыт') &&
    узел('захват-приказ-потери').classList.contains('скрыт'));
