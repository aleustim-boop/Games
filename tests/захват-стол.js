class Узел {
  constructor(тег, атрибуты) {
    this.тег = тег;
    this.атрибуты = атрибуты || {};
    this.дети = [];
    this.родитель = null;
    this._текст = '';
    this.обработчики = {};
    this.value = '';
    this.записиСтиля = {};
    this.прямыеПравкиСтиля = [];
    const узел = this;
    this.style = new Proxy({}, {
      get(_, свойство) {
        if (свойство === 'setProperty') return function (имя, значение) { узел.записиСтиля[имя] = String(значение); };
        return undefined;
      },
      set(_, свойство) {
        узел.прямыеПравкиСтиля.push(String(свойство));
        return true;
      }
    });
    const самУзел = this;
    this.classList = {
      add(имя) {
        const список = самУзел.классы();
        if (список.indexOf(имя) === -1) список.push(имя);
        самУзел.атрибуты.class = список.join(' ');
      },
      remove(имя) {
        самУзел.атрибуты.class = самУзел.классы().filter(function (к) { return к !== имя; }).join(' ');
      },
      contains(имя) { return самУзел.классы().indexOf(имя) !== -1; }
    };
  }
  классы() { return (this.атрибуты.class || '').split(/\s+/).filter(Boolean); }
  get children() { return this.дети; }
  get textContent() {
    return this.дети.length ? this.дети.map(function (д) { return д.textContent; }).join('') : this._текст;
  }
  set textContent(значение) {
    this.дети = [];
    this._текст = String(значение);
  }
  setAttribute(имя, значение) { this.атрибуты[имя] = String(значение); }
  getAttribute(имя) { return имя in this.атрибуты ? this.атрибуты[имя] : null; }
  removeAttribute(имя) { delete this.атрибуты[имя]; }
  appendChild(ребёнок) {
    ребёнок.родитель = this;
    this.дети.push(ребёнок);
    return ребёнок;
  }
  replaceChildren() { this.дети = []; this._текст = ''; }
  addEventListener(событие, действие) {
    (this.обработчики[событие] = this.обработчики[событие] || []).push(действие);
  }
  вызвать(событие, данные) {
    const список = this.обработчики[событие] || [];
    список.forEach(function (д) { д(данные || {}); });
    return список.length;
  }
  // Карта лежит в левом верхнем углу экрана: сдвига рамки у проверки нет.
  getBoundingClientRect() { return { left: 0, top: 0 }; }
  querySelector(селектор) {
    const имя = селектор.replace(/^\./, '');
    return всеУзлы(this).filter(function (у) { return у !== this && у.classList.contains(имя); }, this)[0] || null;
  }
}

function всеУзлы(корень) {
  const итог = [корень];
  корень.дети.forEach(function (д) { всеУзлы(д).forEach(function (у) { итог.push(у); }); });
  return итог;
}

function узлыКласса(корень, имяКласса) {
  return всеУзлы(корень).filter(function (у) { return у.classList.contains(имяКласса); });
}

function разобратьРазметку(текст) {
  const без = ['input', 'br', 'img'];
  const корень = new Узел('корень', {});
  let текущий = корень;
  const шаблон = /<!--[\s\S]*?-->|<\/(\w+)\s*>|<(\w+)((?:\s+[^\s=>\/]+(?:\s*=\s*(?:"[^"]*"|'[^']*'|[^\s>]+))?)*)\s*\/?>|([^<]+)/g;
  let совпадение;
  while ((совпадение = шаблон.exec(текст)) !== null) {
    if (совпадение[1]) {
      if (текущий.родитель) текущий = текущий.родитель;
    } else if (совпадение[2]) {
      const атрибуты = {};
      const разбор = /([^\s=]+)(?:\s*=\s*"([^"]*)")?/g;
      let а;
      while ((а = разбор.exec(совпадение[3] || '')) !== null) атрибуты[а[1]] = а[2] === undefined ? '' : а[2];
      const узел = new Узел(совпадение[2], атрибуты);
      текущий.appendChild(узел);
      if (без.indexOf(совпадение[2]) === -1) текущий = узел;
    } else if (совпадение[4] && совпадение[4].trim()) {
      if (!текущий.дети.length) текущий._текст += совпадение[4].replace(/\s+/g, ' ').trim();
    }
  }
  return корень;
}

function сделатьДокумент() {
  const html = fs.readFileSync(path.join(КОРЕНЬ, 'захват.html'), 'utf8');
  const начало = html.indexOf('<section id="экран-игры"');
  const конец = html.indexOf('</section>', начало);
  if (начало === -1 || конец === -1) throw new Error('В захват.html нет раздела экран-игры');
  const корень = разобратьРазметку(html.slice(начало, конец + '</section>'.length));
  const поId = {};
  всеУзлы(корень).forEach(function (у) { if (у.атрибуты.id) поId[у.атрибуты.id] = у; });
  return {
    корень: корень,
    getElementById(id) { return поId[id] || null; },
    createElement(тег) { return new Узел(тег, {}); }
  };
}

// ---------- партия для проверки ----------

function сделатьПартию() {
  const партия = Правила.новаяПартия({ игроки: ['a', 'b', 'c', 'd', 'e', 'f'], люди: ['a'] }, function () { return 0.5; });
  return партия;
}

function номераОбластейУ(партия, ключ) {
  const итог = [];
  партия.хозяева.forEach(function (х, н) { if (н > 0 && х === ключ) итог.push(н); });
  return итог;
}

// Пара соседних областей «моя → чужая» (удар) и «моя → моя» (перевод), если такие есть.
function найтиПары(партия) {
  const карта = Правила.картаПартии(партия);
  const соседство = Карты.соседство(карта);
  const мои = номераОбластейУ(партия, 'a');
  const пары = { удар: null, перевод: null };
  мои.forEach(function (из) {
    (соседство[из] || []).forEach(function (в) {
      if (партия.хозяева[в] !== 'a' && партия.хозяева[в] !== null && !пары.удар) пары.удар = { из: из, в: в };
      if (партия.хозяева[в] === 'a' && !пары.перевод) пары.перевод = { из: из, в: в };
    });
  });
  return пары;
}

function текстыВсего(корень) {
  return всеУзлы(корень).filter(function (у) { return !у.дети.length; }).map(function (у) { return у._текст; }).join(' | ');
}

