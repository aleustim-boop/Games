function проверитьМестоКарты() {
  const партия = сделатьПервуюПартию();
  const карта = Правила.картаПартии(партия);
  const ширина = 358;
  const высотаКарты = КартаВид.геометрия(карта, ширина).высота;
  const окно = Math.round(высотаКарты + 60);
  const без = ЗахватСтол.местоКарты(партия, ширина, окно, 0);
  const близко = function (а, б) { return Math.abs(а - б) <= 0.5; };
  проверка('Д-10б: без отступа карта по центру окна (ноль найденного — провал)', близко(без.высота, высотаКарты) && близко(без.y, 30), JSON.stringify(без));
  проверка('Д-10б: отступ не задан — то же место', JSON.stringify(ЗахватСтол.местоКарты(партия, ширина, окно)) === JSON.stringify(без));

  // 1) Карта помещается над отступом: место без отступа, поэлементно.
  const помещается = ЗахватСтол.местоКарты(партия, ширина, окно, 20);
  проверка('Д-10б: карта помещается над отступом — место = без отступа, прыжка нет',
    близко(помещается.y, без.y) && близко(помещается.x, без.x) && близко(помещается.ширина, без.ширина) && близко(помещается.высота, без.высота), JSON.stringify(помещается));

  // 2) Не помещается, но по высоте ≤ границы: тот же масштаб, низ карты на границе.
  const сдвиг = ЗахватСтол.местоКарты(партия, ширина, окно, 40);
  проверка('Д-10б: не помещается — масштаб тот же', близко(сдвиг.ширина, без.ширина) && близко(сдвиг.высота, без.высота), JSON.stringify(сдвиг));
  проверка('Д-10б: не помещается — низ карты ровно на границе (y = граница − высота), сдвиг 10 px, а не 30',
    близко(сдвиг.y + сдвиг.высота, окно - 40) && близко(без.y - сдвиг.y, 10), JSON.stringify(сдвиг));

  // 3) Выше границы: вписана в границу, y = 0.
  const вписана = ЗахватСтол.местоКарты(партия, ширина, окно, 100);
  проверка('Д-10б: выше границы — вписана в границу, y = 0',
    вписана.y === 0 && близко(вписана.высота, окно - 100) && вписана.ширина < без.ширина, JSON.stringify(вписана));
  проверка('Д-10б: вписанная карта по центру по ширине', близко(вписана.x, (ширина - вписана.ширина) / 2), JSON.stringify(вписана));

  // Без высоты окна (node) отступ ничего не меняет.
  const безОкна = ЗахватСтол.местоКарты(партия, ширина, 0, 50);
  проверка('Д-10б: без высоты окна — карта от верхнего края', безОкна.y === 0 && близко(безОкна.высота, высотаКарты), JSON.stringify(безОкна));
}

// Вид ряда чипов читается из того же css, что и рисует (ТЗ 8.4): чип 32 и не сжимается (иначе замер ширины
// врёт), зазор есть, запасная строка той же высоты 32 и режется «…» — пульт не прыгает.
function проверитьОформлениеЧипов() {
  const текст = fs.readFileSync(довод('--чипы-css') || путьОформления, 'utf8');
  const правило = function (селектор) {
    const найдено = new RegExp('(^|\\n)' + селектор.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\s*\\{([^}]*)\\}').exec(текст);
    return найдено ? найдено[2] : '';
  };
  const ряд = правило('.захват-чипы');
  const чип = правило('.захват-чип');
  const строка = правило('.захват-чипы__строка');
  проверка('П4: в css есть правила ряда, чипа и строки (ноль найденного — провал)', ряд !== '' && чип !== '' && строка !== '');
  проверка('П4: у ряда чипов есть зазор', /(^|[^-])gap:\s*[1-9]/.test(ряд), ряд);
  проверка('П4: чип не сжимается (flex: 0 0 auto) — ширина узла честная', /flex:\s*0 0 auto/.test(чип), чип);
  const высотаЧипа = (/(^|[^-])height:\s*(\d+)px/.exec(чип) || [])[2];
  const высотаСтроки = (/(^|[^-])height:\s*(\d+)px/.exec(строка) || [])[2];
  проверка('П4: строка той же высоты, что чип (32)', высотаЧипа === '32' && высотаСтроки === высотаЧипа, высотаЧипа + ' / ' + высотаСтроки);
  проверка('П4: строка режется «…»', /text-overflow:\s*ellipsis/.test(строка) && /white-space:\s*nowrap/.test(строка) && /overflow:\s*hidden/.test(строка), строка);
}

// ---------- П8: метка «экран-игры--лист», пока открыт лист стола (ТЗ 8.4.2, 8.4.3) ----------

function проверитьМеткуЛиста() {
  const документ = сделатьДокумент();
  const узел = function (id) { return документ.getElementById(id); };
  const экран = узел('экран-игры');
  проверка('П8: в разметке есть #экран-игры и листы стола (ноль найденного — провал)',
    !!экран && !!узел('захват-приказ') && !!узел('захват-карточка') && !!узел('захват-журнал'));
  if (!экран) return;
  const часы = сделатьЧасы();
  const партия = сделатьПартию();
  const пары = найтиПары(партия);
  проверка('П8: есть пара «моя → чужая» (ноль найденного — провал)', !!пары.удар);
  if (!пары.удар) return;
  партия.войска[пары.удар.из] = 4;
  const стол = ЗахватСтол.создать({ документ: документ, время: часы.время, таймер: часы.таймер, слушатели: {} });
  стол.начатьРаунд(партия, 'a', { имена: { a: 'Вы' } });
  const раскладка = стол.показатьСлой(ШИРИНА_КАРТЫ);
  const точка = function (номер) {
    const ш = раскладка.шайбы.filter(function (с) { return с.область === номер; })[0];
    const в = стол.вид();
    return ш ? { x: ш.x * в.зум + в.сдвигX, y: ш.y * в.зум + в.сдвигY } : { x: -999, y: -999 };
  };
  const карта = узел('захват-карта');
  const вниз = function (т) { карта.вызвать('pointerdown', { pointerId: 1, clientX: т.x, clientY: т.y }); };
  const вверх = function (т) { карта.вызвать('pointerup', { pointerId: 1, clientX: т.x, clientY: т.y }); };
  const метка = function () { return экран.classList.contains('экран-игры--лист'); };
  const раз = function () { return экран.классы().filter(function (к) { return к === 'экран-игры--лист'; }).length; };
  const открыть = function () { return стол.открытьПриказ(пары.удар.из, пары.удар.в).принято; };

  проверка('П8: до листа метки нет', !метка());
  проверка('П8: лист приказа открылся', открыть());
  проверка('П8: открыт лист приказа — метка есть', метка() && !узел('захват-приказ').classList.contains('скрыт'));
  проверка('П8: метка — только класс, без правок вида', экран.прямыеПравкиСтиля.length === 0 && Object.keys(экран.записиСтиля).length === 0);

  // Все пути закрытия: «Отмена», «Ударить», касание карты, «Закрыть» карточки, новый раунд, закрытьЛисты (выход, листы экрана).
  узел('захват-приказ-отмена').вызвать('click');
  проверка('П8: «Отмена» — метка снята', !метка());
  открыть();
  узел('захват-приказ-отдать').вызвать('click');
  проверка('П8: «Ударить» — приказ отдан, лист закрыт', стол.черновик().приказы.length === 1 && узел('захват-приказ').classList.contains('скрыт'),
    JSON.stringify(стол.черновик().приказы));
  проверка('П8: «Ударить» — метка снята', !метка());

  открыть();
  const доКасания = JSON.stringify(стол.черновик());
  const своя = пары.удар.из;
  вниз(точка(своя));
  вверх(точка(своя));
  проверка('П8: касание карты над листом — лист закрыт, метка снята', узел('захват-приказ').classList.contains('скрыт') && !метка());
  проверка('П8: касание карты над листом — только «Отмена»: войско не поставлено, черновик тот же',
    JSON.stringify(стол.черновик()) === доКасания, JSON.stringify(стол.черновик()));

  // Долгое касание при открытом листе приказа: приказ закрывается, открывается карточка (ТЗ 8.4.3).
  // При остатке долгое касание открывает «Поставить сюда» экрана, поэтому сперва ставим всё.
  расставитьВсё(стол, партия);
  открыть();
  вниз(точка(своя));
  часы.пройти(ЗахватСтол.ДОЛГОЕ_КАСАНИЕ_МС + 10);
  вверх(точка(своя));
  проверка('П8: долгое касание над листом — открыта карточка, приказ закрыт, метка одна',
    !узел('захват-карточка').classList.contains('скрыт') && узел('захват-приказ').classList.contains('скрыт') && раз() === 1,
    экран.атрибуты.class);
  узел('захват-карточка-закрыть').вызвать('click');
  проверка('П8: «Закрыть» карточки — метка снята', !метка());

  // Два листа подряд: метка одна и снимается, когда закрыт последний.
  открыть();
  стол.открытьКарточку(своя);
  проверка('П8: приказ, потом карточка — метка ровно одна', раз() === 1 && узел('захват-приказ').classList.contains('скрыт'), экран.атрибуты.class);
  стол.закрытьЛисты();
  проверка('П8: закрытьЛисты (выход, лист экрана) — метка снята', !метка());

  // Лист экрана (журнал) открыт после стол.закрытьЛисты(): стол его метку не снимает.
  стол.открытьКарточку(своя);
  стол.закрытьЛисты();
  узел('захват-журнал').classList.remove('скрыт');
  стол.закрытьЛисты();
  проверка('П8: открыт журнал экрана — стол метку не снимает', метка());
  узел('захват-журнал').classList.add('скрыт');
  стол.закрытьЛисты();
  проверка('П8: журнал закрыт — метка снята', !метка());

  открыть();
  стол.начатьРаунд(партия, 'a', { имена: { a: 'Вы' } });
  проверка('П8: новый раунд — лист закрыт, метка снята', узел('захват-приказ').classList.contains('скрыт') && !метка());
}

