  const открыт = стол.открытьПриказ(пары.удар.из, пары.удар.в);
  проверка('лист приказа открывается', открыт.принято === true, открыт.причина);
  проверка('лист виден (нет класса «скрыт»)', !узел('захват-приказ').classList.contains('скрыт'));
