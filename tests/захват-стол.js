  const до = JSON.stringify(стол.черновик());
  const правкаОтменой = стол.отменить();
  проверка('Готово блокирует: «Отменить» отказан', правкаОтменой.принято === false);
  const правкаПриказа = стол.открытьПриказ(пары.удар.из, пары.удар.в);
  проверка('Готово блокирует: лист приказа не открывается', правкаПриказа.принято === false &&
    узел('захват-приказ').classList.contains('скрыт'));
  const правкаУбрать = стол.убратьПриказ();
  проверка('Готово блокирует: приказ не убрать', правкаУбрать.принято === false);
