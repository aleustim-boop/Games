'use strict';

/* =====================================================================
   БИЛЕТЫ НА ПАРТИЮ С БОТОМ СТРОЯТСЯ ИЗ РЕЕСТРА ИГР.

   Что проверяем. server/билеты.js раньше знал одну игру — дурака:
   список игр и уровни ботов были вшиты под него. Теперь список игр,
   длительность партии, срок билета и перевод уровней в цену берутся
   из поля «бот» в js/игры-реестр.js (план штаб/план-рейтинг-бот-и-счёт.md,
   Э3.1 и Э3.2). Билет выдаётся только игре, у которой есть «бот» И
   в способОчков записано 'билет' — это слово дописывает этап игры,
   когда её экран начинает сдавать билеты. Проверка без сети, часы
   подаются доводом «сейчас».

   ФАЗА А — реестр как есть:
     0) в реестре есть игры с «бот» (ноль — провал) и среди них все
        девять игр с ботом из решения штаба;
     А) у дурака 'билет' есть; игры с «бот», но без 'билет', получают
        прежний отказ «очки пока не начисляются»;
     2) дурак — ровно как до реестра: 40 с, три часа, три уровня из
        js/game.js (СЛОЖНОСТИ), 39 с — отказ, 3 ч с лишним — просрочен.
   ФАЗА Б — тот же реестр, но всем играм с «бот» в памяти дописано
   'билет' (как будет, когда все игровые этапы сдадут):
     1) у КАЖДОЙ игры с «бот»: билет выдаётся на каждый её уровень;
        чужое слово уровня — отказ; раньше срока — «слишком короткая»;
        после срока — партия засчитана, в билете слово цены;
     3) нарды «мастер» стоит как сложный бот, «сложный» нард — как обычный;
     4) монополия «обычный» → 1 очко, «лёгкий» — отказ;
     5) у катана билет жив через 4 часа;
     6) игра без «бот» (2048) и неизвестная игра — отказ.

   ЛОМАЮЩИЕ ЗАПУСКИ (обязаны покраснеть). Настоящие файлы не трогаются:
       node tests/билеты-из-реестра.js --сломать <копия реестра>
         копия js/игры-реестр.js во временной папке (например, у нард
         убрано поле «бот») подставляется вместо настоящего реестра;
       node tests/билеты-из-реестра.js --файл=<копия билеты.js>
         копия server/билеты.js (например, прежняя, с вшитым дураком)
         исполняется вместо настоящей; её require ищутся от папки server/.

   Обычный запуск:
       node tests/билеты-из-реестра.js
   ===================================================================== */

const path = require('path');
const os = require('os');
const fs = require('fs');
const Module = require('module');

const КОРЕНЬ = path.join(__dirname, '..');
const ПУТЬ_РЕЕСТРА = path.join(КОРЕНЬ, 'js', 'игры-реестр.js');
const ПУТЬ_БИЛЕТОВ = path.join(КОРЕНЬ, 'server', 'билеты.js');

/* Игры с ботом по решению штаба (план, раздел 1, «Какие игры витрины
   получают рейтинг», плюс дурак). Их пропажа из реестра — провал. */
const ИГРЫ_С_БОТОМ = ['дурак', 'шахматы', 'шашки', 'нарды', 'деберц', 'домино', 'морской-бой', 'катан', 'монополия'];

const номерСломать = process.argv.indexOf('--сломать');
const КОПИЯ_РЕЕСТРА = номерСломать !== -1 ? process.argv[номерСломать + 1] : '';
const аргФайл = process.argv.find(function (а) { return а.startsWith('--файл='); });
const КОПИЯ_БИЛЕТОВ = аргФайл ? аргФайл.slice('--файл='.length) : '';

/* Рейтинг (его требует билеты.js) уводим во временную папку —
   боевые данные не задеваем. */
const ПАПКА_ДАННЫХ = path.join(os.tmpdir(), 'билеты-из-реестра-данные-' + process.pid);
process.env.ДАННЫЕ_ИГРЫ = ПАПКА_ДАННЫХ;

let проверок = 0;
let провалов = 0;
function проверить(условие, текст) {
  проверок++;
  if (условие) { console.log('  ✓ ' + текст); return; }
  провалов++;
  console.log('  ✗ ' + текст);
}

/** Положить готовый объект вместо модуля по настоящему пути: билеты.js
 * просит '../js/игры-реестр.js' и получит подмену. */
function подложитьМодуль(путь, exports) {
  const подмена = new Module(путь);
  подмена.filename = путь;
  подмена.exports = exports;
  подмена.loaded = true;
  require.cache[путь] = подмена;
}

/** Реестр, у которого всем играм с «бот» дописано 'билет'. */
function реестрСБилетомУВсех(исходный) {
  function дописать(з) {
    if (з && з.бот && з.способОчков.indexOf('билет') === -1) з.способОчков.push('билет');
    return з;
  }
  return {
    все: function () { return исходный.все().map(дописать); },
    поКлючу: function (ключ) { return дописать(исходный.поКлючу(ключ)); }
  };
}

/** Загрузить server/билеты.js заново (или его копию из --файл=) поверх
 * того реестра, что сейчас лежит в require.cache. */
function загрузитьБилеты() {
  delete require.cache[ПУТЬ_БИЛЕТОВ];
  if (!КОПИЯ_БИЛЕТОВ) return require(ПУТЬ_БИЛЕТОВ);
  /* Копию исполняем под именем настоящего файла: её require('./рейтинг.js')
     и '../js/…' находят файлы проекта, а сама копия лежит где угодно. */
  const модуль = new Module(ПУТЬ_БИЛЕТОВ, module);
  модуль.filename = ПУТЬ_БИЛЕТОВ;
  модуль.paths = Module._nodeModulePaths(path.dirname(ПУТЬ_БИЛЕТОВ));
  модуль._compile(fs.readFileSync(КОПИЯ_БИЛЕТОВ, 'utf8'), ПУТЬ_БИЛЕТОВ);
  return модуль.exports;
}

/* Метка времени вне реальных часов машины. */
const Т_НОЛЬ = 1800000000000;
const СЕК = 1000;
const ЧАС = 60 * 60 * СЕК;

/* Каждый сценарий — свой номер игрока: лимиты сдач («раз в 40 с»,
   «20 в сутки») общие на номер, и так они друг другу не мешают. */
let следующийНомер = 700000001;
function новыйНомер() { return следующийНомер++; }

/** Выдать билет и сразу сдать его через «через» мс. */
function выдатьИСдать(билеты, игра, уровень, исход, через) {
  билеты.забытьВсё();
  const кто = новыйНомер();
  const выд = билеты.выдать(кто, игра, уровень, Т_НОЛЬ);
  if (!выд || !выд.ок) return выд || { ок: false, причина: 'нет ответа' };
  return билеты.погасить(кто, выд.билет, исход, 'Проверка', Т_НОЛЬ + через);
}

function словами(ответ) {
  if (!ответ) return 'нет ответа';
  return ответ.ок ? (ответ.очков + ' очк., цена «' + ответ.уровень + '»') : ответ.причина;
}

try {
  if (КОПИЯ_РЕЕСТРА) {
    if (!fs.existsSync(КОПИЯ_РЕЕСТРА)) throw new Error('копия реестра не найдена: ' + КОПИЯ_РЕЕСТРА);
    подложитьМодуль(ПУТЬ_РЕЕСТРА, require(path.resolve(КОПИЯ_РЕЕСТРА)));
    console.log('ЛОМАЮЩИЙ ЗАПУСК: реестр подменён копией ' + КОПИЯ_РЕЕСТРА);
  }
  if (КОПИЯ_БИЛЕТОВ) {
    if (!fs.existsSync(КОПИЯ_БИЛЕТОВ)) throw new Error('копия билеты.js не найдена: ' + КОПИЯ_БИЛЕТОВ);
    console.log('ЛОМАЮЩИЙ ЗАПУСК: вместо server/билеты.js исполняется ' + КОПИЯ_БИЛЕТОВ);
  }
  const реестр = require(ПУТЬ_РЕЕСТРА);
  const рейтинг = require(path.join(КОРЕНЬ, 'server', 'рейтинг.js'));
  const правилаДурака = require(path.join(КОРЕНЬ, 'js', 'game.js'));

  /* =================== ФАЗА А: реестр как есть =================== */
  console.log('Фаза А: реестр как есть');
  let билеты = загрузитьБилеты();

  const сБотом = реестр.все().filter(function (з) { return !!з.бот; });
  проверить(сБотом.length > 0, '0) в реестре есть игры с полем «бот»: ' + сБотом.length);
  ИГРЫ_С_БОТОМ.forEach(function (ключ) {
    const запись = реестр.поКлючу(ключ);
    проверить(!!(запись && запись.бот), '0) у игры «' + ключ + '» есть поле «бот»');
  });

  const запДурака = реестр.поКлючу('дурак');
  проверить(!!запДурака && запДурака.способОчков.indexOf('билет') !== -1, 'А) у дурака в способОчков есть \'билет\'');
  сБотом.forEach(function (запись) {
    if (запись.способОчков.indexOf('билет') !== -1) return;
    билеты.забытьВсё();
    const ответ = билеты.выдать(новыйНомер(), запись.ключ, Object.keys(запись.бот.уровни)[0], Т_НОЛЬ);
    проверить(ответ && ответ.ок === false && ответ.причина === 'За партии с ботом в этой игре очки пока не начисляются',
      'А) ' + запись.ключ + ' без \'билет\' — прежний отказ (' + (ответ && (ответ.причина || 'выдан')) + ')');
  });

  /* ---------- 2) дурак — как до реестра ---------- */
  проверить(билеты.БИЛЕТ_ЖИВЁТ === 3 * ЧАС, '2) дурак: БИЛЕТ_ЖИВЁТ = 3 ч');
  проверить(!!запДурака && !!запДурака.бот &&
    JSON.stringify(Object.keys(запДурака.бот.уровни)) === JSON.stringify(правилаДурака.СЛОЖНОСТИ) &&
    правилаДурака.СЛОЖНОСТИ.every(function (у) { return запДурака.бот.уровни[у] === у; }),
    '2) дурак: уровни в реестре ровно СЛОЖНОСТИ из js/game.js, цена слово в слово');
  правилаДурака.СЛОЖНОСТИ.forEach(function (уровень) {
    билеты.забытьВсё();
    const выд = билеты.выдать(новыйНомер(), 'дурак', уровень, Т_НОЛЬ);
    проверить(выд && выд.ок === true && выд.партияНеКорочеСекунд === 40, '2) дурак «' + уровень + '»: билет, партия не короче 40 с');
  });
  const рано = выдатьИСдать(билеты, 'дурак', 'обычный', 'победа', 39 * СЕК);
  проверить(рано.ок === false && рано.причина === 'Партия слишком короткая, чтобы её засчитать', '2) дурак: 39 с — отказ');
  const живой = выдатьИСдать(билеты, 'дурак', 'обычный', 'победа', 3 * ЧАС - СЕК);
  проверить(живой.ок === true, '2) дурак: за секунду до 3 ч билет жив (' + словами(живой) + ')');
  const поздно = выдатьИСдать(билеты, 'дурак', 'сложный', 'победа', 3 * ЧАС + СЕК);
  проверить(поздно.ок === false && поздно.причина === 'Билет просрочен', '2) дурак: через 3 ч с секундой — «Билет просрочен»');
  const сложный = выдатьИСдать(билеты, 'дурак', 'сложный', 'победа', 41 * СЕК);
  проверить(сложный.ок === true && сложный.очков === рейтинг.ЦЕНА.сложный.победа,
    '2) дурак: победа над сложным — ' + словами(сложный) + ' (ЦЕНА.сложный.победа = ' + рейтинг.ЦЕНА.сложный.победа + ')');
  const чужойДурак = билеты.выдать(новыйНомер(), 'дурак', 'мастер', Т_НОЛЬ);
  проверить(чужойДурак && чужойДурак.ок === false && чужойДурак.причина === 'Такого уровня бота нет', '2) дурак «мастер» — отказ');

  /* ========= ФАЗА Б: всем играм с «бот» дописано 'билет' ========= */
  console.log('Фаза Б: всем играм с «бот» дописано \'билет\' (подмена реестра в памяти)');
  подложитьМодуль(ПУТЬ_РЕЕСТРА, реестрСБилетомУВсех(реестр));
  билеты = загрузитьБилеты();

  /* ---------- 1) каждая игра с «бот» ---------- */
  сБотом.forEach(function (запись) {
    const игра = запись.ключ;
    const бот = запись.бот;
    const уровни = Object.keys(бот.уровни || {});
    проверить(уровни.length > 0, '1) ' + игра + ': уровни бота названы (' + уровни.join(', ') + ')');
    уровни.forEach(function (уровень) {
      билеты.забытьВсё();
      const кто = новыйНомер();
      const выд = билеты.выдать(кто, игра, уровень, Т_НОЛЬ);
      проверить(выд && выд.ок === true && выд.партияНеКорочеСекунд === бот.партияНеКорочеСекунд,
        '1) ' + игра + ' «' + уровень + '»: билет выдан, партия не короче ' +
        (выд && (выд.ок ? выд.партияНеКорочеСекунд + ' с' : выд.причина)));
      if (!выд || !выд.ок) return;
      const пог = билеты.погасить(кто, выд.билет, 'победа', 'Проверка', Т_НОЛЬ + бот.партияНеКорочеСекунд * СЕК + СЕК);
      проверить(пог && пог.ок === true && пог.уровень === бот.уровни[уровень],
        '1) ' + игра + ' «' + уровень + '»: после срока засчитано — ' + словами(пог));
    });

    билеты.забытьВсё();
    const чужой = билеты.выдать(новыйНомер(), игра, 'непобедимый', Т_НОЛЬ);
    проверить(чужой && чужой.ок === false && чужой.причина === 'Такого уровня бота нет',
      '1) ' + игра + ': чужое слово уровня — отказ (' + (чужой && (чужой.причина || 'выдан')) + ')');

    const рано = выдатьИСдать(билеты, игра, уровни[0], 'победа', бот.партияНеКорочеСекунд * СЕК - СЕК);
    проверить(рано && рано.ок === false && /слишком короткая/.test(рано.причина),
      '1) ' + игра + ': за секунду до срока — «слишком короткая» (' + словами(рано) + ')');
  });

  /* ---------- 3) нарды: «мастер» = сложный ---------- */
  const нарды = реестр.поКлючу('нарды');
  const срокНард = нарды && нарды.бот ? нарды.бот.партияНеКорочеСекунд * СЕК : 0;
  const мастер = выдатьИСдать(билеты, 'нарды', 'мастер', 'победа', срокНард + СЕК);
  проверить(мастер.ок === true && мастер.уровень === 'сложный' && мастер.очков === рейтинг.ЦЕНА.сложный.победа,
    '3) нарды «мастер»: как сложный бот — ' + словами(мастер));
  const сложныйНард = выдатьИСдать(билеты, 'нарды', 'сложный', 'победа', срокНард + СЕК);
  проверить(сложныйНард.ок === true && сложныйНард.очков === рейтинг.ЦЕНА.обычный.победа,
    '3) нарды «сложный»: как обычный бот — ' + словами(сложныйНард));
  const обычныйНард = билеты.выдать(новыйНомер(), 'нарды', 'обычный', Т_НОЛЬ);
  проверить(обычныйНард && обычныйНард.ок === false, '3) нарды: слова «обычный» у бота нард нет — отказ');

  /* ---------- 4) монополия ---------- */
  const монополия = выдатьИСдать(билеты, 'монополия', 'обычный', 'победа', 301 * СЕК);
  проверить(монополия.ок === true && монополия.очков === 1, '4) монополия «обычный»: победа — ' + словами(монополия));
  const лёгкийМон = билеты.выдать(новыйНомер(), 'монополия', 'лёгкий', Т_НОЛЬ);
  проверить(лёгкийМон && лёгкийМон.ок === false, '4) монополия «лёгкий» — отказ');

  /* ---------- 5) катан: билет жив через 4 часа ---------- */
  (function () {
    билеты.забытьВсё();
    const кто = новыйНомер();
    const выд = билеты.выдать(кто, 'катан', 'обычный', Т_НОЛЬ);
    /* Уборка просроченных при чужой выдаче не должна снести билет катана
       по сроку дурака. */
    билеты.выдать(новыйНомер(), 'дурак', 'обычный', Т_НОЛЬ + 4 * ЧАС - СЕК);
    const пог = выд && выд.ок ? билеты.погасить(кто, выд.билет, 'победа', 'Проверка', Т_НОЛЬ + 4 * ЧАС) : выд;
    проверить(пог && пог.ок === true, '5) катан: билет принят через 4 ч (' + словами(пог) + ')');
  })();

  /* ---------- 6) игры без бота ---------- */
  билеты.забытьВсё();
  const без = билеты.выдать(новыйНомер(), '2048', 'обычный', Т_НОЛЬ);
  проверить(без && без.ок === false && /не начисляются/.test(без.причина), '6) 2048 (без «бот») — отказ: ' + (без && без.причина));
  const нет = билеты.выдать(новыйНомер(), 'крестики', 'обычный', Т_НОЛЬ);
  проверить(нет && нет.ок === false, '6) неизвестная игра — отказ');
} catch (беда) {
  проверок++;
  провалов++;
  console.log('  ✗ проверка оборвалась: ' + беда.message);
}

try { fs.rmSync(ПАПКА_ДАННЫХ, { recursive: true, force: true }); } catch (е) { /* временная папка необязательна */ }

console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
process.exit(провалов > 0 ? 1 : 0);
