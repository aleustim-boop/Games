/* =====================================================================
   КОНЕЦ ПАРТИИ ПО СОГЛАСИЮ: СЛОВА ИТОГА И ЛИЧНЫЙ СЧЁТ (игры/дурак/game.js).

   Что проверяет. Когда стол дурака (3+ человек) закончил партию по
   согласию, сервер присылает вид.поСогласию = true, а итог — 'победа'
   (скинул карты и сохранил победу), 'поражение' (ушёл из партии) или
   вообще без итога. Страница обязана:
     - без итога не принимать конец за «потерю связи», а рассказать
       «Партия закончена по согласию» (слова — из раздела 4 плана
       штаб/план-дурак-согласие.md, дословно);
     - в личный счёт не писать «по согласию», но писать победу и поражение;
     - не играть звук победы/поражения на «по согласию»;
     - оставить видной кнопку «Сыграть ещё»;
     - со старым сервером (поля поСогласию нет) говорить прежние слова.

   Как проверяет. Поднимает НАСТОЯЩИЙ игры/дурак/game.js в песочнице vm (документ —
   из tests/поддельный-браузер.js, как tests/дурак-круг-тексты.js) и
   прогоняет через настоящие партияИзВида() и подвестиСетевойИтог() те же
   виды, что пришлют сервер. Рейтинг и звуки в песочнице — перехватчики.

   Запуск:
       node tests/дурак-согласие-тексты.js              — обычный прогон
       node tests/дурак-согласие-тексты.js --сломать N  — берёт НЕ настоящий
         игры/дурак/game.js, а его испорченную КОПИЮ во временной папке и обязан
         покраснеть. Порчи:
           1 — результатСетевойПартии не знает поСогласию (вернётся «связь потеряна»);
           2 — записатьПартиюВСчёт пишет и 'по-согласию';
           3 — чемКончилосьДляМеня не смотрит на поСогласию;
           4 — тексты итога не знают поСогласию;
           5 — партияИзВида не передаёт поСогласию;
           6 — в именах ушедших снова считается «ушёл» (вышедший победителем попадает в поражения).
         Файл проекта проверка не трогает и не портит.
   ===================================================================== */

