/** Одна партия двоих: победил первый, если не сказано иначе. */
function партия(победитель, проигравший, ничья) {
  return [
    { номер: победитель.номер, имя: победитель.имя, победил: !ничья, ничья: Boolean(ничья) },
    { номер: проигравший.номер, имя: проигравший.имя, победил: false, ничья: Boolean(ничья) }
  ];
}

/** Партия с ботом: человек против машины. */
function сБотом(человек, победил, сила) {
  return [
    { номер: человек.номер, имя: человек.имя, победил: победил, ничья: false },
    { этоБот: true, сложность: сила || 'обычный', победил: !победил, ничья: false }
  ];
}

function наполнить() {
  /* Сила попадает в таблицу не сразу: она должна быть измерена надёжно,
     а для этого нужно несколько десятков партий с живыми людьми. Поэтому
     играем помногу — иначе экран честно скажет «в таблице силы пока
     никого нет», и снимать будет опять нечего.
     Разброс делаем нарочный: сильные, середина и хвост, чтобы на снимке
     были и медали, и обычные строки, и своя строка НЕ на первом месте —
     иначе не видно, как её выделяют. */
  /* Сила становится надёжной не от числа партий вообще, а когда разброс
     измерения сойдётся. Опытом: на пятнадцати игроках это примерно триста
     кругов — тогда «в таблице силы» появляются все пятнадцать. */
  const ПАРТИЙ = 300;
  /* Своя доля побед нарочно посередине: тогда своя строка оказывается
     не первой, и видно, как её выделяют среди чужих. */
  const доляПобед = [0.67, 0.80, 0.74, 0.70, 0.66, 0.62, 0.58, 0.55, 0.48, 0.42, 0.38, 0.34, 0.30, 0.26, 0.22];

  for (let круг = 0; круг < ПАРТИЙ; круг++) {
    for (let i = 0; i < ЛЮДИ.length; i++) {
      const я = ЛЮДИ[i];
      const соперник = ЛЮДИ[(i + 1 + (круг % (ЛЮДИ.length - 1))) % ЛЮДИ.length];
      if (соперник.номер === я.номер) continue;
      /* Кто победил — по доле побед этого игрока: так у людей выходит
         разная сила, а не одинаковая. */
      const мояДоля = доляПобед[i];
      const чужаяДоля = доляПобед[ЛЮДИ.indexOf(соперник)];
      const япобедил = ((круг * 37 + i * 13) % 100) / 100 < мояДоля / (мояДоля + чужаяДоля);
      рейтинг.учестьПартию('дурак', партия(япобедил ? я : соперник, япобедил ? соперник : я));
    }
  }

  /* Пара партий с ботами и ничьих — чтобы в очках была не только победа
     над человеком, и чтобы у кого-то осталась пометка «примерно». */
  ЛЮДИ.forEach(function (человек, номер) {
    if (номер % 3 === 0) рейтинг.учестьПартию('дурак', сБотом(человек, true, 'сложный'));
    if (номер % 4 === 0) рейтинг.учестьПартию('дурак', партия(человек, ЛЮДИ[(номер + 2) % ЛЮДИ.length], true));
  });
}

/** Собрать ответ ровно так, как его собирает дверь /рейтинг в сервере. */
function ответДвери(игра, кто) {
  const срез = рейтинг.срезДляИгрока(игра, кто);
  return {
    ок: true,
    узналиВас: true,
    игра: срез.игра,
    всего: срез.всего,
    яВТаблице: срез.яВТаблице,
    я: срез.я,
    верхушка: срез.верхушка,
    вокругМеня: срез.вокругМеня,
    сила: срез.сила
  };
}

/* ------------------------------------------------------------------ */

(async () => {
  console.log('Наполненная таблица рейтинга. Страница: ' + АДРЕС);
  console.log('Своя папка данных: ' + СВОЯ_ПАПКА + ' (данные владельца не трогаем)');

  наполнить();
  const ответ = ответДвери('дурак', Я);
  console.log('  в таблице человек: ' + ответ.всего + ', я в таблице: ' + ответ.яВТаблице +
    ', строк в верхушке: ' + (ответ.верхушка || []).length +
    ', вокруг меня: ' + (ответ.вокругМеня || []).length +
    ', сила есть: ' + Boolean(ответ.сила));

  /* Верхушка у сервера короткая нарочно (первые три), остальное — соседи
     вокруг меня. Вместе это и есть таблица, которую видит человек. */
  const строкВОтвете = (ответ.верхушка || []).length + (ответ.вокругМеня || []).length;
  проверить(строкВОтвете >= 8, 'в ответе набралось строк: ' + строкВОтвете +
    ' (верхушка ' + (ответ.верхушка || []).length + ' + вокруг меня ' + (ответ.вокругМеня || []).length + ')');
  проверить(ответ.всего >= 15, 'в рейтинге пятнадцать и больше человек: ' + ответ.всего);
  проверить(!!ответ.сила, 'вторая мера (сила) в ответе есть');

  const браузер = await chromium.launch();
  const окно = await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, deviceScaleFactor: 2 });
  const страница = await окно.newPage();
  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
    красные.push('консоль: ' + м.text());
  });

  await подготовитьПодделку(страница, { версия: '8.0', полныйЭкран: 'дают' });
  /* Русский адрес сверяем по раскодированному пути — иначе шаблон
     с кириллицей не совпадёт и запрос уйдёт мимо (см.
     tests/ловушка-кириллицы-в-перехвате.js). */
  let перехватов = 0;
  const включитьПерехват = () => перехватить(страница, '/рейтинг', function (путь, запрос) {
    перехватов++;
    let игра = 'дурак';
    try {
      const тело = JSON.parse(запрос.postData() || '{}');
      if (тело && тело.игра) игра = тело.игра;
    } catch (сбой) { /* тела может не быть */ }
    путь.fulfill({
      status: 200,
      contentType: 'application/json; charset=utf-8',
      body: JSON.stringify(ответДвери(игра, Я))
    });
  });

  await страница.goto(АДРЕС);
  await страница.waitForTimeout(600);

  // Витрина → дурак → игра с ботом → рекорды → рейтинг игроков
  await страница.click('#кнопка-игра-дурак');
  await страница.waitForTimeout(250);
  await страница.click('#кнопка-режим-бот');
  await страница.waitForTimeout(250);
  await страница.click('#кнопка-рекорды');
  await страница.waitForTimeout(400);
  await страница.click('#кнопка-рейтинг-игроков');
  await страница.waitForTimeout(900);

  /* Перехват включаем ТОЛЬКО СЕЙЧАС. Кнопку «Рейтинг игроков» страница
     показывает по своей проверке доступности, и если подменять ответы
     раньше, кнопка не появляется вовсе — сначала даём игре решить самой,
     а потом просим её спросить таблицу заново. */
  await включитьПерехват();
  await страница.evaluate(() => {
    const кнопки = [...document.querySelectorAll('#экран-рейтинга-игроков button')];
    const дурак = кнопки.find((к) => /дурак/i.test(к.textContent || ''));
    if (дурак) дурак.click();
  });
  await страница.waitForTimeout(1200);

  проверить(перехватов > 0, 'страница и правда спросила таблицу у сервера (перехватов ' + перехватов + ')');

  /* ---- что видно на экране ---- */
  const видно = await страница.evaluate(() => {
    const э = document.getElementById('экран-рейтинга-игроков');
    /* Имена классов у экрана рейтинга свои, поэтому ищем терпимо:
       всё, в чьём классе есть слово «строка». */
    const строки = [...э.querySelectorAll('[class*="строка"]')];
    /* Свою строку ищем двумя способами сразу: по виду (класс) и по подписи
       «(вы)». Класс могут переименовать, а слово в строке видит человек —
       если пропадёт и оно, значит своя строка перестала отличаться. */
    const своя = строки.filter((с) =>
      /сво|мо[её]|--я\b|_я\b/i.test(с.className) || /\(вы\)/i.test(с.textContent || ''));
    /* Медаль — кружок места у первой тройки. Ищем и по классу, и по виду:
       у первых трёх номер обычно оформлен иначе, чем у остальных. */
    const медали = [...э.querySelectorAll('.медаль, [class*="медал"], [class*="место--"]')];
    const примерно = [...э.querySelectorAll('[class*="примерн"], [title*="примерн"]')]
      .concat([...э.querySelectorAll('*')].filter((у) => !у.children.length && /≈/.test(у.textContent || '')));
    const ширины = строки.map((с) => Math.round(с.getBoundingClientRect().width));
    return {
      строк: строки.length,
      своих: своя.length,
      классСвоей: своя.length ? своя[0].className : (строки.length ? 'ни одна из ' + строки.length + ': ' + строки.map(с => (с.textContent||'').replace(/s+/g,' ').slice(0,18)).join(' | ') : 'строк нет'),
      медалей: медали.length,
      примерно: примерно.length,
      ширинаЭкрана: window.innerWidth,
      максШирина: ширины.length ? Math.max.apply(null, ширины) : 0,
      прокрутка: document.documentElement.scrollWidth,
      первыеСтроки: строки.slice(0, 4).map((с) => (с.textContent || '').replace(/\s+/g, ' ').trim().slice(0, 60))
    };
  });
  console.log('  строк на экране: ' + видно.строк + ', своя выделена: ' + видно.своих +
    ', медалей: ' + видно.медалей + ', знаков «примерно»: ' + видно.примерно);
  видно.первыеСтроки.forEach((с) => console.log('     · ' + с));

  проверить(видно.строк >= 8, 'таблица на экране наполнена: строк ' + видно.строк);
  проверить(видно.своих >= 1, 'своя строка выделена отдельным видом (класс «' + видно.классСвоей + '»)');
  проверить(видно.максШирина <= видно.ширинаЭкрана + 1,
    'строки не шире экрана: ' + видно.максШирина + ' при ' + видно.ширинаЭкрана);
  проверить(видно.прокрутка <= видно.ширинаЭкрана + 1,
    'страница не поехала вбок от длинного имени: ' + видно.прокрутка);

  await страница.screenshot({ path: ПАПКА_СНИМКОВ + 'таблица-силы-наполненная.png', fullPage: true });
  console.log('  снимок: ' + ПАПКА_СНИМКОВ + 'таблица-силы-наполненная.png');

  /* ---- вторая мера: очки ---- */
  const переключили = await страница.evaluate(() => {
    /* Кнопку второй меры ищем по надписи, а не по имени: имя может
       поменяться, а слово на кнопке видит и человек. */
    const кнопки = [...document.querySelectorAll('#экран-рейтинга-игроков button')];
    const очки = кнопки.find((к) => /очк/i.test(к.textContent || ''));
    if (очки) { очки.click(); return очки.textContent.trim(); }
    return null;
  });
  await страница.waitForTimeout(800);
  console.log('  переключатель второй меры: ' + (переключили ? '«' + переключили + '»' : 'не нашёлся'));
  await страница.screenshot({ path: ПАПКА_СНИМКОВ + 'таблица-очков-наполненная.png', fullPage: true });
  console.log('  снимок: ' + ПАПКА_СНИМКОВ + 'таблица-очков-наполненная.png');

  проверить(красные.length === 0, 'консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));

  await браузер.close();
  try { fs.rmSync(СВОЯ_ПАПКА, { recursive: true, force: true }); } catch (сбой) { /* не страшно */ }
  console.log('\nИтог: провалов ' + провалов);
  process.exit(провалов ? 1 : 0);
})().catch((о) => { console.error('Стенд упал: ' + (о && о.stack || о)); process.exit(2); });
