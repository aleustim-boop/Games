const { chromium, подготовитьПодделку, перехватить } = require('./браузер-робот.js');

const ПОРТ = Number(process.argv[2]) || 8080;
const АДРЕС = 'http://127.0.0.1:' + ПОРТ + '/';
const ПАПКА_СНИМКОВ = 'tests/скриншоты/';

/* Свою папку данных ставим ДО того, как подключим серверные модули:
   путь они читают при первом обращении. */
