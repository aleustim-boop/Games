/** Нажать, если кнопка есть и видна. Путь к экранам стал короче,
    и часть кнопок на дороге может отсутствовать. */
async function нажатьЕслиЕсть(страница, примета) {
  try {
    const видна = await страница.evaluate((п2) => {
      const к = document.querySelector(п2);
      return !!(к && к.offsetParent !== null);
    }, примета);
    if (!видна) return false;
    await страница.click(примета, { timeout: 4000 });
    return true;
  } catch (сбой) { return false; }
}

