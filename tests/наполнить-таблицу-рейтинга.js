process.env.GAMES_DATA = СВОЯ_ПАПКА;

const рейтинг = require(path.join(__dirname, '..', 'server', 'рейтинг.js'));

let провалов = 0;
function проверить(условие, слова) {
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}

