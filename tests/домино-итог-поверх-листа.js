let номерВида = 0;
function видИтога() {
  const п = Д.раздать(null, { игроки: МЕСТА.slice(0, МЕСТ), цельДомино: 100 });
  for (let i = 0; i < 4000 && п.игра.фаза !== 'итог' && !п.завершена; i++) {
    const кто = Д.чейХод(п);
    if (!кто) break;
    Д.ходЗаБота(п, кто, 'обычный');
  }
  const места = п.игроки.map(function (ключ, i) {
    return { ключ: ключ, имя: ИМЕНА[i], этоБот: false, хозяин: i === 0, наСвязи: true, ушёл: false, хочетЕщё: false };
  });
  return Д.видДляИгрока(п, п.игроки[0], { код: 'ТЕСТ', этап: 'партия', версия: ++номерВида, номерСобытия: 1,
    события: '', места: места, мест: МЕСТ, мойНомер: 0, яХозяин: true, можноНачать: false, парами: false, соперникПришёл: true,
    соперникНаСвязи: true, имяСоперника: ИМЕНА[1] });
}

/* ---------- Что делаем в странице ---------- */

/** В СТРАНИЦЕ: показать стол как после ответа сервера. */
function показатьСтол(вид) {
  if (!window.ИграПоСети || typeof window.ИграПоСети.показатьВид !== 'function') return 'нет window.ИграПоСети.показатьВид';
  try { window.ИграПоСети.показатьВид(вид); } catch (е) { return 'исключение при показе: ' + е.message; }
  return '';
}

/** В СТРАНИЦЕ: где кнопка «⋯» на столе (видимая), где середина окна итога и состояние окна/листа. */
function замер() {
  const окно = document.getElementById('дом-результат');
  const лист = document.getElementById('лист-игры');
  const кнопки = Array.from(document.querySelectorAll('#экран-игры [data-меню]')).map(function (к) { const р = к.getBoundingClientRect(); return { x: р.left + р.width / 2, y: р.top + р.height / 2, w: р.width, h: р.height }; })
    .filter(function (р) { return р.w > 0 && р.h > 0; });
  const ро = окно.getBoundingClientRect();
  const строка = лист && лист.querySelector('.лист-ещё__строка:not(.скрыт)');
  let листСверху = false;
  if (строка && !лист.classList.contains('скрыт')) {
    const с = строка.getBoundingClientRect();
    const верхний = document.elementFromPoint(с.left + с.width / 2, с.top + с.height / 2);
    листСверху = Boolean(верхний && лист.contains(верхний));
  }
  return { окноОткрыто: окно.open, листОткрыт: Boolean(лист && !лист.classList.contains('скрыт')), листСверху: листСверху,
    кнопки: кнопки, окно: { left: ро.left, right: ро.right, top: ро.top, bottom: ро.bottom }, W: document.documentElement.clientWidth, H: window.innerHeight };
}

/** В СТРАНИЦЕ: средняя разница цвета (0–255) между двумя PNG одного размера, переданными как base64. */
async function наибольшаяРазницаСнимков(пара) {
  const загрузить = async б64 => {
    const и = new Image(); и.src = 'data:image/png;base64,' + б64; await и.decode();
    const к = document.createElement('canvas'); к.width = и.width; к.height = и.height;
    const ctx = к.getContext('2d'); ctx.drawImage(и, 0, 0); return ctx.getImageData(0, 0, к.width, к.height).data;
  };
  const а = await загрузить(пара[0]), б = await загрузить(пара[1]);
  if (а.length !== б.length || а.length === 0) return 999;
  let сумма = 0, число = 0;   // среднее, а не наибольшее: буквы сглаживаются чуть иначе, а затемнение меняет всю полосу
  for (let i = 0; i < а.length; i++) if (i % 4 !== 3) { сумма += Math.abs(а[i] - б[i]); число++; }
  return сумма / число;
}

/* ---------- Прогон одного размера ---------- */

async function прогнатьОдин(браузер, адрес, размер, снимки) {
  const п = размер.w + 'px: ';
  const контекст = await браузер.newContext({ viewport: { width: размер.w, height: размер.h }, reducedMotion: 'reduce', hasTouch: false });
  const ошибки = [];
  const страница = await контекст.newPage();
  страница.on('pageerror', function (о) { ошибки.push('исключение: ' + о.message); });
  страница.on('console', function (с) { if (с.type() === 'error' && !/Failed to load resource/.test(с.text())) ошибки.push('консоль: ' + с.text()); });
  await подготовитьПодделку(страница, {});
  try {
    await страница.goto(адрес + 'домино.html?сервер=' + encodeURIComponent('http://127.0.0.1:1'));
    await страница.waitForFunction(function () { return window.ИграПоСети && window.ЛистЕщё; }, null, { timeout: 8000 });
    await страница.waitForTimeout(400);
    const ош = await страница.evaluate(показатьСтол, видИтога());
    проверить(ош === '', п + 'стол показан через ИграПоСети.показатьВид' + (ош ? ' (' + ош + ')' : ''));
    await страница.waitForTimeout(500);

    let м = await страница.evaluate(замер);
    if (!проверить(м.окноОткрыто, п + '[окно-открыто] окно итогов открыто до нажатия')) return;
    if (!проверить(м.кнопки.length >= 1, п + '[кнопка-найдена] видимая кнопка «⋯» нашлась (найдено: ' + м.кнопки.length + ')')) return;

    // Нажатие мимо кнопки: фон окна внизу экрана (левый нижний угол), окно и лист не меняются.
    await страница.mouse.click(2, м.H - 2);
    await страница.waitForTimeout(250);
    let после = await страница.evaluate(замер);
    проверить(после.окноОткрыто && !после.листОткрыт, п + '[мимо] нажатие по фону не по «⋯» окно не прячет и лист не открывает (окно: ' + после.окноОткрыто + ', лист: ' + после.листОткрыт + ')');

    // Нажатие по «⋯» — как пальцем: по координатам.
    await страница.mouse.click(м.кнопки[0].x, м.кнопки[0].y);
    await страница.waitForTimeout(350);
    после = await страница.evaluate(замер);
    проверить(!после.окноОткрыто, п + '[окно-спрятано] после нажатия по «⋯» окно итогов закрыто');
    проверить(после.листОткрыт && после.листСверху, п + '[лист-открыт] лист «⋯» открыт и лежит сверху (открыт: ' + после.листОткрыт + ', сверху: ' + после.листСверху + ')');
    await страница.screenshot({ path: path.join(снимки, 'домино-итог-поверх-листа-' + размер.w + '.png') });

    // Возврат окна кнопкой на столе (лист сперва закрываем: он закрывает собой стол).
    await страница.evaluate(function () { document.querySelector('#лист-игры').classList.add('скрыт'); });
    const вернулось = await страница.evaluate(function () {
      const к = document.getElementById('дом-действие');
      if (!к || к.disabled) return 'кнопка «Результат раунда» неактивна';
      к.click();
      return document.getElementById('дом-результат').open ? '' : 'окно не открылось';
    });
    проверить(вернулось === '', п + '[окно-вернуть] «Результат раунда» снова открывает окно' + (вернулось ? ' (' + вернулось + ')' : ''));
    // Верхняя строка над окном: там, где окно опущено под неё (низкий экран), затемнение её не трогает —
    // снимок полосы с открытым окном байт в байт равен снимку без окна. На высоком экране затемнение прежнее.
    const полоса = { x: 0, y: 0, width: размер.w, height: Math.round(м.кнопки[0].y + м.кнопки[0].h / 2 + 6) };
    const точкаНаФоне = await страница.evaluate(function (к) { return document.elementFromPoint(к.x, к.y) === document.getElementById('дом-результат'); }, м.кнопки[0]);
    const сОкном = await страница.screenshot({ clip: полоса });
    await страница.evaluate(function () { document.getElementById('дом-результат').close(); });
    await страница.waitForTimeout(150);
    const безОкна = await страница.screenshot({ clip: полоса });
    const разница = await страница.evaluate(наибольшаяРазницаСнимков, [сОкном.toString('base64'), безОкна.toString('base64')]);
    const одинаковы = разница <= 3;   // допуск на сглаживание букв; затемнение полосы даёт заметно больше
    if (размер.h <= 700) {
      проверить(точкаНаФоне, п + '[полоса-светлая] под центром «⋯» при открытом окне — фон окна, а не его содержимое');
      проверить(одинаковы, п + '[полоса-светлая] верхняя строка под открытым окном не затемнена (снимок полосы такой же, как без окна; средняя разница цвета: ' + разница.toFixed(1) + ')');
    } else {
      проверить(!одинаковы, п + '[полоса-прежняя] на высоком экране затемнение осталось как раньше (полоса с окном отличается от полосы без него)');
    }
    проверить(ошибки.length === 0, п + 'ошибок в консоли нет' + (ошибки.length ? ': ' + ошибки.join(' | ') : ''));
  } finally {
    await контекст.close();
  }
}

async function прогнать(подмены, снимки) {
  fs.mkdirSync(снимки, { recursive: true });
  const сервер = await поднятьСерверФайлов(подмены);
  const адрес = 'http://127.0.0.1:' + сервер.address().port + '/';
  console.log('=== Домино: окно итогов и лист «⋯» ===');
  console.log('файлы: ' + адрес + '\nснимки: ' + снимки);
  let браузер = null;
  try {
    браузер = await chromium.launch();
    for (const размер of РАЗМЕРЫ) {
      console.log('\n--- ' + размер.w + '×' + размер.h + ' ---');
      await прогнатьОдин(браузер, адрес, размер, снимки);
    }
  } finally {
    if (браузер) await браузер.close();
    сервер.close();
    console.log('\nСервер файлов закрыт.');
  }
  console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
  process.exitCode = провалов > 0 ? 1 : 0;
}

