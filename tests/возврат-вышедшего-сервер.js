/**
 * Стол на «мест» мест, все места — люди (тот же приём, что
 * tests/досрочный-конец-сервер.js). Ответ: { комната, код, места: {A: ключ},
 * пропуски: {A: ...}, номера: {A: телеграм} }.
 */
function собратьСтол(игра, мест, телеграмС) {
  const создана = комнаты.создатьКомнату(новыйАдрес(), { имя: ИМЕНА[0], телеграм: телеграмС, игра: игра, мест: мест });
  if (!создана.ок) throw new Error('комната не создалась: ' + создана.причина);
  const хозяин = комнаты.найтиИгрока(создана.код, создана.пропуск);
  const места = { A: хозяин.ктоЯ };
  const пропуски = { A: создана.пропуск };
  const номера = { A: телеграмС };
  for (let i = 1; i < мест; i++) {
    const вход = комнаты.войтиВКомнату(создана.код, { имя: ИМЕНА[i], телеграм: телеграмС + i });
    if (!вход.ок) throw new Error(КЛЮЧИ[i] + ' не вошёл: ' + вход.причина);
    места[КЛЮЧИ[i]] = комнаты.найтиИгрока(создана.код, вход.пропуск).ктоЯ;
    пропуски[КЛЮЧИ[i]] = вход.пропуск;
    номера[КЛЮЧИ[i]] = телеграмС + i;
  }
  if (хозяин.комната.этап === 'ожидание') {
    const начали = комнаты.сделатьХод(хозяин.комната, хозяин.ктоЯ, { действие: 'начать' });
    if (!начали.принято) throw new Error('партия не началась: ' + начали.причина);
  }
  return { комната: хозяин.комната, код: создана.код, места: места, пропуски: пропуски, номера: номера };
}

function партияИдёт(комната) {
  return комната.этап === 'игра' && Boolean(комната.партия) && !комната.партия.завершена;
}

/** Любой законный ход деберца за того, чья очередь, — через дверь комнаты. */
function ходДеберца(комната, кто) {
  const и = комната.партия.игра;
  const игрок = комната.партия.игроки.indexOf(кто);
  let намерение;
  if (и.фаза === 'торговля') {
    намерение = { действие: 'торг', масть: ПравилаДеберца.обязанВыбрать(и) ? ПравилаДеберца.вариантыКозыря(и)[0] : null };
  } else if (и.фаза === 'игра') {
    намерение = { действие: 'карта', id: ПравилаДеберца.доступные(и, игрок)[0].id };
  } else {
    намерение = { действие: и.фаза === 'взятка' ? 'взятка' : 'раздача' };
  }
  return комнаты.сделатьХод(комната, кто, намерение);
}

/** Ходить за людей деберца, пока «кто» не сделает свой первый ход. */
function деберцДоХода(комната, кто) {
  for (let шаг = 0; шаг < 40; шаг++) {
    if ((комната.игроки[кто].ходовВПартии || 0) > 0) return true;
    const ходит = комната.партия.игроки[комната.партия.игра.ход];
    const игрок = комната.игроки[ходит];
    if (!игрок || игрок.этоБот) return false;
    if (!ходДеберца(комната, ходит).принято) return false;
  }
  return false;
}

/**
 * «Сходил» — чтобы уход был сдачей. В деберце — настоящими ходами;
 * в дураке и домино — счётчиком, как tests/досрочный-конец-вид.js.
 */
function сходил(стол, кто) {
  const к = стол.комната;
  if (к.игра === 'деберц') return деберцДоХода(к, стол.места[кто]);
  к.игроки[стол.места[кто]].ходовВПартии = 1;
  return true;
}

/** Рука места в виде игрока и рука того же места за столом — длины и есть ли карты. */
function рукаСвоя(к, место, вид) {
  const п = к.партия;
  if (к.игра === 'деберц') {
    const i = п.игроки.indexOf(место);
    const вВиде = вид.деберц && вид.деберц.рука;
    return Array.isArray(вВиде) && вВиде.length > 0 && вВиде.length === п.игра.руки[i].length;
  }
  if (к.игра === 'домино') {
    const i = п.игроки.indexOf(место);
    const вВиде = вид.домино && вид.домино.рука;
    return Array.isArray(вВиде) && вВиде.length > 0 && JSON.stringify(вВиде) === JSON.stringify(п.игра.руки[i]);
  }
  const вВиде = вид.мояРука;
  return Array.isArray(вВиде) && вВиде.length > 0 && вВиде.length === (п.руки[место] || []).length;
}

/** Место с данным ключом в «застолом» вида. */
function местоВВиде(вид, место) {
  return (вид.застолом || []).find(function (м) { return м.номер === номерМеста(место); }) || null;
}

function голос(комната, кто, за) {
  return комнаты.сделатьХод(комната, кто, { действие: 'закончить-голос', за: за });
}

function предложить(комната, кто) {
  return комнаты.сделатьХод(комната, кто, { действие: 'закончить-предложить' });
}

/** Служебные поля возврата и сам старый пропуск не должны встречаться в тексте. */
function естьУтечка(текст, пропуск) {
  return /пропускВозврата|партияВозврата|вернулсяВПартию/.test(текст) || (пропуск && текст.indexOf(пропуск) !== -1);
}

