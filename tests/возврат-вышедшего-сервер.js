/**
 * Сценарий 3. Дурак на троих: «вышел победителем» и потом возврат.
 * Что делает сервер сейчас, закреплено ниже; беды — в отчёте, не здесь.
 */
function случайПобедитель() {
  console.log('\nДурак на 3: вышел победителем (сбросил все карты) — и вернулся');
  const { стол, к, место, буква } = поставитьПобедителя(95200);
  проверить(Boolean(буква), 'нашли место победителя: «' + место + '»');
  if (!буква) return;
  const п = к.партия;
  const игрок = к.игроки[место];
  const пропуск = стол.пропуски[буква];
  const другие = п.игроки.filter(function (и) { return и !== место; });
  проверить(ктоХодит(к) !== место && другие.indexOf(ктоХодит(к)) !== -1, 'очередь у одного из двух остальных, не у победителя');
  const рукиДругих = JSON.stringify(другие.map(function (и) { return п.руки[и]; }));

  комнаты.выйти(к, место);
  проверить(игрок.вышелПобедителем === true && игрок.сдался !== true && игрок.этоБот === true,
            'вышел победителем: «вышелПобедителем», не «сдался», место водит бот');
  проверить(партияИдёт(к) && п.проигравшие.length === 0, 'партия у остальных идёт, проигравших нет');
  проверить(комнаты.можноВернуться(стол.код, пропуск) === true, 'можноВернуться — «да»');

  const итог = комнаты.вернутьсяПоПропуску(стол.код, пропуск);
  проверить(итог.ок === true && итог.ктоЯ === место && итог.ужеЗаСтолом === false, 'возврат победителя принят, место его собственное');
  const вид = комнаты.показатьИгроку(к, место);
  проверить(Array.isArray(вид.мояРука) && вид.мояРука.length === 0, 'в его виде рука пустая: карты не выдуманы');
  проверить(п.руки[место].length === 0, 'на сервере рука места по-прежнему пустая');
  проверить(п.выбывшие.filter(function (м) { return м === место; }).length === 1, 'в «выбывших» он один раз: из круга игроков не вернулся');
  проверить(п.игроки.length === 3 && new Set(п.игроки).size === 3 && Object.keys(п.руки).length === 3, 'мест в партии по-прежнему три, без двойников');
  проверить((вид.застолом || []).length === 3 && (вид.застолом || []).filter(function (з) { return з.этоЯ === true; }).length === 1,
            'в виде за столом трое, «этоЯ» — ровно один');
  проверить(игрок.этоБот === false && игрок.сдался !== true, 'бота на месте нет, «сдался» не появился');
  проверить(JSON.stringify(другие.map(function (и) { return п.руки[и]; })) === рукиДругих, 'руки остальных не тронуты');
  проверить(партияИдёт(к) && другие.indexOf(ктоХодит(к)) !== -1, 'партия идёт, очередь по-прежнему у остальных, не у вернувшегося');
  const повтор = комнаты.вернутьсяПоПропуску(стол.код, пропуск);
  проверить(повтор.ок === true && повтор.ужеЗаСтолом === true, 'повтор — «вы за столом»');

  /* Второй выход и второй возврат победителя. */
  комнаты.выйти(к, место);
  проверить(игрок.этоБот === true && игрок.вышелПобедителем === true && партияИдёт(к), 'второй выход: бот на месте, партия идёт');
  const второй = комнаты.вернутьсяПоПропуску(стол.код, пропуск);
  проверить(второй.ок === true && второй.ужеЗаСтолом === false, 'второй возврат принят');
  проверить(п.выбывшие.filter(function (м) { return м === место; }).length === 1 && п.руки[место].length === 0,
            'после второго возврата: в «выбывших» один раз, рука пустая');

  /* «Вышел из комнаты и вернулся» — заново войти по коду с тем же Telegram-номером. */
  комнаты.выйти(к, место);
  const вход = комнаты.войтиВКомнату(стол.код, { имя: ИМЕНА[КЛЮЧИ.indexOf(буква)], телеграм: стол.номера[буква] });
  console.log('  · сервер на «войти по коду» после выхода посреди партии: ' + JSON.stringify({ ок: вход.ок, причина: вход.причина }));
  проверить(вход.ок === false, 'заново войти по коду в идущую партию — отказ (' + вход.причина + ')');
  проверить(п.игроки.length === 3 && new Set(п.игроки).size === 3 && партияИдёт(к), 'после попытки войти мест по-прежнему три, партия идёт');
  проверить(п.руки[место].length === 0 && Object.keys(п.руки).length === 3, 'после попытки войти рука не выдумана');
  проверить(к.игроки[место].этоБот === true, 'место по-прежнему водит бот, чужой не сел');
  const ещёРаз = комнаты.вернутьсяПоПропуску(стол.код, пропуск);
  проверить(ещёРаз.ок === true && ещёРаз.ужеЗаСтолом === false, 'после неудачной попытки войти старый пропуск всё ещё возвращает за стол');
}

const ХОДИТ_ПО_ПРИЗНАКУ = 'можноВернуться';

