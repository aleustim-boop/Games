'use strict';

/* =====================================================================
   ШТАБ/СПИСКИ.JS БОЛЬШЕ НЕ ДОПИСЫВАЕТ ШУМ «ПОХОЖЕЕ» В ЗАДАЧИ.md.

   Зачем. 16 сентября штаб заметил: при каждой пересборке (node штаб/
   списки.js) программа сравнивала текст задач из очереди с заголовками
   коммитов git и почти всегда находила «похожее» — на живой очереди
   срабатывало на 63 из 66 строк, потому что слова вроде «дашборд» или
   «проверка» общие для половины задач и коммитов проекта. Пометка
   «⚠️ в записях git есть похожее» дописывалась почти к каждой строке —
   и в ЗАДАЧИ.md (файл, который штаб перечитывает на каждом шаге), и
   в штаб/очередь.md. Шум съедал контекст, реального сигнала почти не давая.

   Сам порог похожести живёт в штаб/сделано.js (значимыеСлова,
   похожаяЗапись) — это чужой файл, эта проверка его не трогает и не
   правит. Правка — только в том, КАК штаб/списки.js показывает находку:
   раньше дописывал пометку в сами файлы построчно, теперь — только
   считает и печатает одно число в консоли при запуске, а в ЗАДАЧИ.md
   и штаб/очередь.md пометки вообще нет.

   ДВА ПРОГОНА В ОДНОМ ФАЙЛЕ:

     node tests/штабные-списки-без-шума-похожести.js
       — обычный: очередь из двух пунктов — один специально похож на
       реальный недавний коммит только ОБЩИМ словом («проверка»), это
       и есть тот самый ложный случай, который раньше плодил шум; второй
       по-настоящему близок к недавнему коммиту (несколько общих корней
       подряд, это разумная находка). Проверяем: ни ЗАДАЧИ.md, ни
       штаб/очередь.md НЕ получают построчную пометку «⚠️ в записях git
       есть похожее:» ни для одного из двух пунктов, а в консоли —
       компактная строка со счётчиком, без списка находок.

     node tests/штабные-списки-без-шума-похожести.js --сломать
       — ломающий: берём настоящий текст штаб/списки.js и программой же
       возвращаем в него старый шумный кусок (тот самый, что был до
       правки), кладём временную копию рядом в штаб/ и запускаем её на
       тех же данных. Если старый шум вернулся — ЗАДАЧИ.md/очередь.md
       обязаны показать построчную пометку. Не показали — значит эта
       проверка не отличает испорченный код от рабочего, то есть сама
       проверка сломана, и это и есть провал ломающего прогона.

   Оба прогона работают с настоящими ЗАДАЧИ.md, штаб/списки.json и
   штаб/очередь.md — других путей штаб/списки.js не знает (пути зашиты
   через __dirname). Поэтому оригиналы читаются в память перед работой
   и возвращаются на место через finally, что бы ни случилось.

   Для похожести проверка полагается на настоящий git log этого
   проекта (сделано.записиGit смотрит реальную историю) — без него
   пункт «похожая» не с чем сравнивать. Пустой git log — проверка
   говорит об этом честно и не подделывает находку.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const корень = path.join(__dirname, '..');
const файлЗадач = path.join(корень, 'ЗАДАЧИ.md');
const файлСписков = path.join(корень, 'штаб', 'списки.json');
const файлОчередиОстальное = path.join(корень, 'штаб', 'очередь.md');
const программа = path.join(корень, 'штаб', 'списки.js');

const сломать = process.argv.includes('--сломать');

// Общий счётчик проверок и провалов — как в остальных файлах tests/.
let проверок = 0;
const провалы = [];

function проверить(условие, что) {
  проверок++;
  if (!условие) {
    провалы.push(что);
    console.log('  ПРОВАЛ: ' + что);
  } else {
    console.log('  ок   ' + что);
  }
}

/* Пометка «⚠️ в записях git есть похожее:» — старый формат, тот, что
   программа раньше дописывала прямо в текст строки таблицы. Двоеточие
   после «похожее» — часть сгенерированного текста (штаб/списки.js,
   было: '⚠️ в записях git есть похожее: «' + ...). Ищем именно так,
   чтобы не спутать с обычным упоминанием этих слов в тексте задачи. */
const СГЕНЕРИРОВАННАЯ_ПОМЕТКА = '⚠️ в записях git есть похожее:';

/* Минимальный, но честный ЗАДАЧИ.md: разделы «Очередь» и «Готово» между
   другими разделами, как в настоящем файле — чтобы проверить и поиск
   границ раздела, а не только текст внутри. */
const тестовыйЗадачиMd =
  '# Задачи проекта (тестовая заготовка)\n\n' +
  '## Раздел до\n\nТекст раздела до.\n\n' +
  '## Очередь: что увидит игрок\n\n(будет переписано программой)\n\n' +
  '## Готово и уже у игроков\n\n| Что | Когда |\n|---|---|\n\n' +
  '## Раздел после\n\nТекст раздела после.\n';

/* Два пункта очереди — оба без приметы «сделано», значит дело решает
   только третий, самый слабый пояс (похожесть по git log):

   - «непохожая» специально задета ОДНИМ общим словом («проверка») с
     реальным недавним коммитом этого проекта, но по смыслу — другая
     задача (проверка хода в шашках vs дашборд после сдачи дня). Ровно
     тот случай, что раньше плодил шум. Важность «потом» — уходит в
     штаб/очередь.md.
   - «похожая» специально пересказывает своими словами недавний
     реальный коммит («дашборд: проверка сдачи дня сдана, очередь
     пересобрана») — несколько общих корней подряд, это разумная
     находка, а не шум. Важность «скоро» — уходит в ЗАДАЧИ.md. */
function списокJson() {
  return JSON.stringify({
    очередь: [
      { что: 'Проверка правильности хода дамкой в шашках', важность: 'потом' },
      { что: 'Дашборд: очередь после проверки сдачи дня пересобрана вручную', важность: 'скоро' }
    ]
  }, null, 2) + '\n';
}

function запуститьПрограмму(путьКПрограмме) {
  return execFileSync(process.execPath, [путьКПрограмме], { cwd: корень, encoding: 'utf8' });
}

/* ---------------------------------------------------------------------
   Ломающий прогон готовит временную «испорченную» копию штаб/списки.js:
   программой же возвращает в текст ровно тот кусок, что был до правки.
   Патчей несколько, и каждый обязан реально что-то заменить — если
   искомый кусок не нашёлся (например файл успели переписать иначе),
   тест обязан упасть с понятной причиной, а не молча собрать не то.
--------------------------------------------------------------------- */
function испорченнаяКопия() {
  let текст = fs.readFileSync(программа, 'utf8');

  const патчи = [
    [
      "function строкаОчереди(п) {\n  const важность = (п.важность === 'потом' || п.важность === 'задел')\n    ? п.важность\n    : '**' + п.важность + '**';\n  const заметка = п.заметка || '';\n  return '| ' + п.что + ' | ' + важность + ' | ' + заметка + ' |\\n';\n}",
      "function строкаОчереди(п, подсказки) {\n  const важность = (п.важность === 'потом' || п.важность === 'задел')\n    ? п.важность\n    : '**' + п.важность + '**';\n  let заметка = п.заметка || '';\n  const подсказка = подсказки.get(п.что);\n  if (подсказка) {\n    заметка += (заметка ? ' ' : '')\n      + '⚠️ в записях git есть похожее: «' + подсказка.что + '» — проверьте, не сделано ли';\n  }\n  return '| ' + п.что + ' | ' + важность + ' | ' + заметка + ' |\\n';\n}"
    ],
    ["function разделОчереди(пункты) {", "function разделОчереди(пункты, подсказки) {"],
    ["for (const п of горящие) раздел += строкаОчереди(п);", "for (const п of горящие) раздел += строкаОчереди(п, подсказки);"],
    ["function файлОчередиОстальное(пункты) {", "function файлОчередиОстальное(пункты, подсказки) {"],
    ["for (const п of остальные) текст += строкаОчереди(п);", "for (const п of остальные) текст += строкаОчереди(п, подсказки);"],
    ["разделОчереди(остались), ЗАГОЛОВОК_ГОТОВО", "разделОчереди(остались, подсказки), ЗАГОЛОВОК_ГОТОВО"],
    ["файлОчередиОстальное(остались), 'utf8'", "файлОчередиОстальное(остались, подсказки), 'utf8'"]
  ];

  for (const [от, к] of патчи) {
    if (текст.indexOf(от) === -1) {
      throw new Error('ломающий прогон: не нашёлся кусок для замены — ' +
        'штаб/списки.js изменился сильнее, чем ждал этот тест: «' + от.slice(0, 60) + '…»');
    }
    текст = текст.replace(от, к);
  }

  const путь = path.join(корень, 'штаб', '_temp-сломанные-списки-для-проверки.js');
  fs.writeFileSync(путь, текст, 'utf8');
  return путь;
}

/* ---------------------------------------------------------------------
   Резервируем настоящие файлы штаба, что бы ни случилось — вернём их.
--------------------------------------------------------------------- */
const резервЗадач = fs.existsSync(файлЗадач) ? fs.readFileSync(файлЗадач, 'utf8') : null;
const резервСписков = fs.existsSync(файлСписков) ? fs.readFileSync(файлСписков, 'utf8') : null;
const резервОчереди = fs.existsSync(файлОчередиОстальное) ? fs.readFileSync(файлОчередиОстальное, 'utf8') : null;

let временнаяПрограмма = null;

try {
  fs.writeFileSync(файлЗадач, тестовыйЗадачиMd, 'utf8');
  fs.writeFileSync(файлСписков, списокJson(), 'utf8');
  fs.writeFileSync(файлОчередиОстальное, '(будет переписано программой)\n', 'utf8');

  if (!сломать) {
    console.log('=== Обычный прогон: похожесть найдена, но в файлы не дописана ===\n');

    const вывод = запуститьПрограмму(программа);
    const итогЗадач = fs.readFileSync(файлЗадач, 'utf8');
    const итогОчереди = fs.readFileSync(файлОчередиОстальное, 'utf8');

    проверить(
      итогЗадач.indexOf(СГЕНЕРИРОВАННАЯ_ПОМЕТКА) === -1,
      'ЗАДАЧИ.md не получил построчную пометку «похожее» для пункта важности «скоро»'
    );
    проверить(
      итогОчереди.indexOf(СГЕНЕРИРОВАННАЯ_ПОМЕТКА) === -1,
      'штаб/очередь.md не получил построчную пометку «похожее» для пункта важности «потом»'
    );
    проверить(
      итогЗадач.indexOf('Проверка правильности хода дамкой в шашках') === -1 ||
      итогОчереди.indexOf('Проверка правильности хода дамкой в шашках') !== -1,
      'пункт важности «потом» лежит в штаб/очередь.md, а не в ЗАДАЧИ.md (проверка не перепутала файлы)'
    );

    // Похожесть реально нашлась (иначе всё выше зелёное просто потому,
    // что сравнивать было не с чем) — счётчик в консоли обязан быть > 0.
    const счётчик = /совпадений: (\d+)/.exec(вывод);
    проверить(
      Boolean(счётчик) && Number(счётчик[1]) >= 1,
      'консоль печатает счётчик находок, и он не нулевой (иначе сравнивать было не с чем)'
    );

    // Старый построчный формат консоли — «  · текст ← «коммит»» — тоже не
    // должен вернуться: иначе шум просто переехал из файла в консоль.
    проверить(
      вывод.indexOf(' ← «') === -1,
      'консоль не печатает старый построчный список находок (только число)'
    );
  } else {
    console.log('=== Ломающий прогон: подсовываем старый шумный код ===\n');

    временнаяПрограмма = испорченнаяКопия();
    запуститьПрограмму(временнаяПрограмма);
    const итогЗадач = fs.readFileSync(файлЗадач, 'utf8');
    const итогОчереди = fs.readFileSync(файлОчередиОстальное, 'utf8');

    проверить(
      итогЗадач.indexOf(СГЕНЕРИРОВАННАЯ_ПОМЕТКА) !== -1 || итогОчереди.indexOf(СГЕНЕРИРОВАННАЯ_ПОМЕТКА) !== -1,
      'старый шумный код на тех же данных вернул построчную пометку «похожее» — ' +
      'значит обычный прогон этой проверки её бы точно заметил, если бы правка отвалилась'
    );
  }
} finally {
  // Возвращаем боевые файлы штаба на место, что бы ни случилось выше.
  if (резервЗадач !== null) fs.writeFileSync(файлЗадач, резервЗадач, 'utf8');
  if (резервСписков !== null) fs.writeFileSync(файлСписков, резервСписков, 'utf8');
  if (резервОчереди !== null) fs.writeFileSync(файлОчередиОстальное, резервОчереди, 'utf8');
  if (временнаяПрограмма && fs.existsSync(временнаяПрограмма)) fs.unlinkSync(временнаяПрограмма);
}

console.log('\n----------------------------------------');
console.log('Итого проверок: ' + проверок + ', провалов: ' + провалы.length);
process.exit(провалы.length > 0 ? 1 : 0);
