async function прогнатьОдно(браузер, адрес, размер, св, папка) {
  const { вид, фазаВиде } = собратьВид(св);
  const контекст = await браузер.newContext({ viewport: { width: размер.w, height: размер.h }, reducedMotion: 'reduce' });
  const ошибки = [];
  const страница = await контекст.newPage();
  страница.on('pageerror', function (о) { ошибки.push('исключение: ' + о.message); });
  страница.on('console', function (с) { if (с.type() === 'error' && !/Failed to load resource/.test(с.text())) ошибки.push('консоль: ' + с.text()); });
  await подготовитьПодделку(страница, {});
  try {
    await страница.goto(адрес + 'домино.html?сервер=' + encodeURIComponent('http://127.0.0.1:1'));
    await страница.waitForFunction(function () { return window.ИграПоСети && window.ЛистЕщё; }, null, { timeout: 8000 });
    await страница.waitForTimeout(400);
    const ошПоказа = await страница.evaluate(показатьСтол, { вид: вид, яСплю: Boolean(св.яСплю), тексты: ТЕКСТЫ_СНА });
    await страница.waitForTimeout(1200);
    const файл = path.join(папка, размер.w + '-' + св.ключ + '.png');
    await страница.screenshot({ path: файл });
    console.log('  снимок: ' + файл);
    const м = await страница.evaluate(замерить);
    разобрать(св, размер, { м: м, ошибки: ошибки, ошПоказа: ошПоказа, фазаВиде: фазаВиде });
  } finally {
    await контекст.close();
  }
}

async function прогнать(подмены, папка) {
  fs.mkdirSync(папка, { recursive: true });
  const сервер = await поднятьСерверФайлов(подмены);
  const адрес = 'http://127.0.0.1:' + сервер.address().port + '/';
  console.log('=== Домино: пометка спящего и итог при моём сне — снимки и замеры ===');
  console.log('файлы: ' + адрес + '\nснимки: ' + папка);
  let браузер = null;
  try {
    браузер = await chromium.launch();
    for (const размер of РАЗМЕРЫ) {
      for (const св of СОСТОЯНИЯ) {
        console.log('\n--- ' + размер.w + '×' + размер.h + ' · ' + св.ключ + ' ---');
        await прогнатьОдно(браузер, адрес, размер, св, папка);
      }
    }
  } finally {
    if (браузер) await браузер.close();
    сервер.close();
    console.log('\nСервер файлов закрыт.');
  }
  console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
  process.exitCode = провалов > 0 ? 1 : 0;
}

