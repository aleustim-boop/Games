const коорд = function (р) { return Math.round(р.x) + ',' + Math.round(р.y) + '–' + Math.round(р.r) + ',' + Math.round(р.b); };

function разобрать(св, размер, р) {
  const п = размер.w + 'px · ' + св.ключ + ': ';
  const м = р.м;
  проверить(р.ошПоказа === '', п + 'стол показан через ИграПоСети.показатьВид' + (р.ошПоказа ? ' (' + р.ошПоказа + ')' : ''));
  проверить(р.фазаВиде === св.фаза, п + 'стол в нужной фазе «' + св.фаза + '» (вышло: ' + р.фазаВиде + ')');
  проверить(м.вбок <= 0, п + 'горизонтальной прокрутки нет (лишних пикселей: ' + м.вбок + ')');
  проверить(м.карточки.length === МЕСТ, п + '[карточка] карточек игроков ' + МЕСТ + ' (найдено: ' + м.карточки.length + ')');

  const спящие = м.карточки.filter(function (к) { return к.спит; });
  if (св.спитСосед !== null) {
    if (проверить(спящие.length === 1, п + '[карточка] ровно одна спящая карточка (найдено: ' + спящие.length + ')')) {
      const к = спящие[0];
      const соседи = м.карточки.filter(function (с) { return !с.спит; });
      const шире = Math.max.apply(null, соседи.map(function (с) { return с.w; }));
      проверить(к.виден && к.вЭкране, п + '[карточка] карточка спящего целиком в экране (' + коорд(к) + ', экран ' + м.W + '×' + м.H + ')');
      проверить(к.w <= шире + 1, п + '[карточка] карточка спящего не шире соседних (' + Math.round(к.w) + ' против ' + Math.round(шире) + ')');
      const бк = к.безКласса;
      проверить(Boolean(бк) && Math.abs(бк.w - к.w) <= 0.5 && Math.abs(бк.h - к.h) <= 0.5,
        п + '[размер-карточки] карточка спящего ' + Math.round(к.w) + '×' + Math.round(к.h) + ' такая же, как без класса сна ' + (бк ? Math.round(бк.w) + '×' + Math.round(бк.h) : 'нет замера'));
      const т = к.притушен;
      if (проверить(т.аватар, п + '[притушен] у спящего есть закрытые кости («аватар»)')) {
        проверить(т.прозрачность <= 0.5 && т.серый, п + '[притушен] спящий притушен: прозрачность ' + т.прозрачность + ' (нужно ≤ 0.5), серый: ' + т.серый);
      }
      проверить(т.зз, п + '[притушен] у спящего есть значок «z z»');
      проверить(т.рамка !== 'dashed', п + '[притушен] рамка карточки спящего не пунктирная (вышло: ' + т.рамка + ')');
      if (проверить(к.меток === 1 && к.метка, п + '[бот-видна] на карточке спящего ровно одна пометка (найдено: ' + к.меток + ')')) {
        const б = к.метка;
        проверить(б.тег === 'em' && б.текст === 'играет бот', п + '[бот-видна] em со словами «играет бот» (вышло: ' + б.тег + ' «' + б.текст + '»)');
        проверить(б.виден, п + '[бот-видна] пометка на виду');
        проверить(!б.срезана, п + '[бот-целиком] слова не обрезаны (ширина узла ' + Math.round(б.w) + ')');
        проверить(б.внутри, п + '[бот-целиком] пометка целиком внутри карточки (пометка ' + коорд(б) + ', карточка ' + коорд(к) + ')');
        проверить(б.шрифт >= 11, п + '[бот-читается] шрифт не мельче 11 (вышло: ' + б.шрифт + ')');
        const нужный = Math.max(к.подписи.мал, к.подписи.имя);
        проверить(к.подписи.мал > 0 && к.подписи.имя > 0 && б.шрифт >= нужный,
          п + '[бот-читается] метка не мельче соседних подписей (метка ' + б.шрифт + ', «костей» ' + к.подписи.мал + ', имя ' + к.подписи.имя + ')');
        const зн = т.значок;
        if (проверить(Boolean(зн), п + '[значок-размер] у значка «z z» есть рамка (absolute, содержимое «z z»)')) {
          проверить(зн.шрифт >= 12, п + '[значок-размер] шрифт «z z» не меньше 12 (вышло: ' + зн.шрифт + ')');
          проверить(зн.x >= к.x - 0.5 && зн.r <= к.r + 0.5 && зн.y >= к.y - 0.5 && зн.b <= к.b + 0.5,
            п + '[значок-место] «z z» целиком внутри карточки (значок ' + коорд(зн) + ', карточка ' + коорд(к) + ')');
          проверить(!(зн.x < б.r - 0.5 && б.x < зн.r - 0.5 && зн.y < б.b - 0.5 && б.y < зн.b - 0.5),
            п + '[значок-место] «z z» не пересекает метку (значок ' + коорд(зн) + ', метка ' + коорд(б) + ')');
        }
        проверить(б.контраст >= 4.5, п + '[бот-читается] цвет читается на фоне карточки (контраст ' + б.контраст.toFixed(1) + ', нужно от 4.5)');
      }
    }
  } else {
    проверить(спящие.length === 0, п + '[нет-метки] спящих карточек нет (найдено: ' + спящие.length + ')');
  }
  // Где бы ни спали — у бодрствующих пометки нет. Не нашли ни одной карточки — выше уже красное.
  const чужиеМетки = м.карточки.filter(function (к) { return !к.спит && к.меток > 0; });
  проверить(м.карточки.length === МЕСТ && чужиеМетки.length === 0, п + '[нет-метки] у неспящих пометки «играет бот» нет (нашлось у: ' + чужиеМетки.map(function (к) { return к.id; }).join(', ') + ')');

  if (св.фаза === 'итог') {
    if (!проверить(м.окно.есть, п + '[окно] окно итога #дом-результат найдено')) { /* ниже нечего мерить */ }
    if (св.яСплю) {
      проверить(m_окноЗакрыто(м), п + '[окно] я сплю — окно итога спрятано (открыто: ' + м.окно.открыто + ')');
      if (проверить(м.плашка.есть && м.плашка.виден, п + '[окно] плашка #плашка-досрочно на экране')) {
        проверить(м.кнопка.есть && м.кнопка.виден && м.кнопка.текст === 'Я здесь', п + '[окно] кнопка «Я здесь» на виду');
        проверить(Boolean(м.кнопка.сама), п + '[окно] кнопку «Я здесь» ничто не закрывает (в её середине: ' + м.кнопка.чтоСверху + ')');
        проверить(Boolean(м.кнопка.вЭкране), п + '[окно] кнопка целиком в экране (' + (м.кнопка.есть ? коорд(м.кнопка) : 'нет') + ')');
      }
    } else {
      проверить(м.окно.открыто === true, п + '[контроль] я не сплю — окно итога открыто (открыто: ' + м.окно.открыто + ')');
    }
  }
  проверить(р.ошибки.length === 0, п + 'ошибок в консоли нет' + (р.ошибки.length ? ': ' + р.ошибки.join(' | ') : ''));
}
function m_окноЗакрыто(м) { return м.окно.есть && м.окно.открыто === false; }

