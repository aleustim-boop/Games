let номерВида = 0;
/** Играем ботом до нужной фазы раунда («игра» — сразу после раздачи). */
function партияВФазе(фаза) {
  const п = Д.раздать(null, { игроки: МЕСТА.slice(0, МЕСТ), цельДомино: 100 });
  for (let i = 0; i < 3000 && п.игра.фаза !== фаза && !п.завершена; i++) {
    const кто = Д.чейХод(п);
    if (!кто) break;
    Д.ходЗаБота(п, кто, 'обычный');
  }
  return п;
}

function собратьВид(св) {
  const п = партияВФазе(св.фаза);
  const места = п.игроки.map(function (ключ, i) {
    return { ключ: ключ, имя: ИМЕНА[i], этоБот: false, хозяин: i === 0, наСвязи: true, ушёл: false, хочетЕщё: false, спит: св.спитСосед === i ? true : undefined };
  });
  const в = Д.видДляИгрока(п, п.игроки[0], { код: 'ТЕСТ', этап: 'партия', версия: ++номерВида, номерСобытия: 1,
    события: '', места: места, мест: МЕСТ, мойНомер: 0, яХозяин: true, можноНачать: false, парами: false, соперникПришёл: true,
    соперникНаСвязи: true, имяСоперника: ИМЕНА[1] });
  if (св.яСплю) в.спит = true;   // как кладёт сервер: только самому спящему, в корень вида
  return { вид: в, фазаВиде: в.домино.фаза };
}

