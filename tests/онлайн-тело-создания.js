const fs = require('fs');
const path = require('path');
const { поднять, сделатьДокумент, сделатьПамять } = require('./поддельный-браузер.js');

const КОРЕНЬ = path.join(__dirname, '..');
const ПОДПИСЬ = 'user=%7B%22id%22%3A1%7D&hash=abc';
const ИМЯ = 'Тест';
const ОСНОВА = { имя: ИМЯ, initData: ПОДПИСЬ };

const проверки = [];
function проверить(условие, текст) {
  проверки.push({ ок: Boolean(условие), текст: текст });
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + текст);
}

function подождать() {
  return new Promise(function (готово) { setTimeout(готово, 0); });
}

/** Путь к копии сеть.js из «--сломать <путь>» или '' — обычный запуск. */
function путьЛомающейКопии() {
  const где = process.argv.indexOf('--сломать');
  if (где === -1) return '';
  const путь = process.argv[где + 1];
  if (!путь || !fs.existsSync(путь)) {
    console.error('после --сломать нужен путь к существующей копии сеть.js');
    process.exit(2);
  }
  return путь;
}

/** Одинаковы ли два плоских тела: те же ключи и те же значения. */
function телаРавны(а, б) {
  const ка = Object.keys(а || {}).sort();
  const кб = Object.keys(б || {}).sort();
  return JSON.stringify(ка) === JSON.stringify(кб) &&
    ка.every(function (к) { return а[к] === б[к]; });
}

function ожидаемое(поля) { return Object.assign({}, поля, ОСНОВА); }

/**
 * Поднять страницу «игра»: при нужде — настоящий модуль лобби ДО сеть.js
 * (как в index.html), затем сеть.js. fetch запоминает запросы; «/создать»
 * отвечает кодом комнаты, остальное висит (к проверке не относится).
 * лобби — настройки для ОнлайнЛобби.подключить или null.
 */
function поднятьСтраницу(исходникСети, игра, лобби, добавкиTelegram) {
  const запросы = [];
  let номерСтола = 0;
  const fetch = function (адрес, настройки) {
    const путь = decodeURIComponent(String(адрес)).replace(/^https?:\/\/[^/]+/, '').replace(/\?.*$/, '');
    let тело = null;
    try { тело = JSON.parse((настройки && настройки.body) || '{}'); } catch (сбой) { тело = null; }
    запросы.push({ путь: путь, тело: тело });
    if (путь === '/создать') {
      номерСтола++;
      const код = 'СТОЛ' + номерСтола;
      return Promise.resolve({ ok: true, status: 200, json: function () {
        return Promise.resolve({ код: код, пропуск: 'п' + номерСтола, состояние: {} });
      } });
    }
    return new Promise(function () {});
  };
  const документ = сделатьДокумент();
  // Кнопка «Создать игру» старого экрана друга: по ней сеть.js признаёт
  // разметку игры с другом и вешает свой обработчик.
  const кнопкаСоздать = документ.узел('button', { id: 'кнопка-создать-игру' });
  документ.body.appendChild(документ.узел('section', { id: 'экран-друга', класс: 'экран' }, кнопкаСоздать));
  const память = сделатьПамять(false);
  let пролог = 'window.ИграСтраницы = ' + JSON.stringify(игра) + ';\n';
  if (лобби) {
    // Настройки стола модуль берёт из окна: проверка меняет их между столами
    // через рез.окно.настройкиСтолаПроверки (функция в JSON не пролезает).
    пролог += 'window.настройкиСтолаПроверки = {};\n' +
      fs.readFileSync(path.join(КОРЕНЬ, 'общее', 'js', 'онлайн-лобби.js'), 'utf8') + '\n' +
      'window.ОнлайнЛобби.подключить(Object.assign(' + JSON.stringify(лобби) + ', {\n' +
      '  настройкиСтола: function () { return Object.assign({}, window.настройкиСтолаПроверки); }\n' +
      '}));\n';
  }
  const рез = поднять(пролог + исходникСети, {
    документ: документ,
    память: память,
    telegram: Object.assign({ initData: ПОДПИСЬ, initDataUnsafe: { user: { first_name: ИМЯ } } }, добавкиTelegram || {}),
    fetch: fetch,
    имяФайла: 'общее/js/сеть.js'
  });
  if (!рез.окно.Сеть || typeof рез.окно.Сеть.создатьКомнату !== 'function') {
    throw new Error('window.Сеть.создатьКомнату не появился');
  }
  return { рез: рез, запросы: запросы, память: память, кнопкаСоздать: кнопкаСоздать };
}

/** Тела всех ушедших «/создать». */
function телаСоздания(стр) {
  return стр.запросы.filter(function (з) { return з.путь === '/создать'; }).map(function (з) { return з.тело; });
}

/** Последнее тело; «сколькоЖдём» — сколько «/создать» должно уйти всего (ноль найденного = провал). */
function последнееТело(стр, что, сколькоЖдём) {
  const тела = телаСоздания(стр);
  проверить(тела.length === сколькоЖдём, что + ': на «/создать» ушло ' + тела.length + ' (ждали ' + сколькоЖдём + ')');
  return тела[тела.length - 1] || {};
}

function сравнить(тело, ждём, что) {
  проверить(телаРавны(тело, ждём), что + ': тело ' + JSON.stringify(ждём) + ' (получили ' + JSON.stringify(тело) + ')');
}

const ЛОББИ_НАРД = { игра: 'нарды', мест: { мин: 2, макс: 2, обычно: 2 } };

/* ---------------------------------------------------------------------
   А. Нарды с модулем; попытки подмены своих полей
   --------------------------------------------------------------------- */

async function проверитьСМодулем(исходникСети) {
  console.log('\n=== А. Нарды: стол через ОнлайнЛобби.создатьСтол() ===');
  const стр = поднятьСтраницу(исходникСети, 'нарды', ЛОББИ_НАРД);
  стр.рез.окно.настройкиСтолаПроверки = {
    контрольШахмат: '5+3',
    игра: 'дурак', имя: 'Чужой', initData: 'подделка',
    мест: 5, открытый: false, компанией: false
  };
  const итог = await стр.рез.окно.ОнлайнЛобби.создатьСтол();
  await подождать();
  проверить(итог && итог.ок === true, 'ОнлайнЛобби.создатьСтол() ответил ок (получили ' + JSON.stringify(итог) + ')');
  const тело = последнееТело(стр, 'нарды через модуль', 1);
  проверить(тело.контрольШахмат === '5+3', 'настройка модуля контрольШахмат доехала');
  проверить(тело.компанией === true && тело.открытый === true, 'компанией и открытый — true, подмена на false не прошла');
  проверить(тело.игра === 'нарды' && тело.имя === ИМЯ && тело.initData === ПОДПИСЬ, 'игра/имя/initData не подменены настройками');
  проверить(тело.мест === 2, 'мест 2 — просьба 5 вне пределов игры не прошла (получили ' + тело.мест + ')');
  сравнить(тело, ожидаемое({ игра: 'нарды', мест: 2, компанией: true, открытый: true, контрольШахмат: '5+3' }), 'нарды через модуль');
  return стр;
}

/* ---------------------------------------------------------------------
   Б. Два стола подряд — настройки первого не протекают
   --------------------------------------------------------------------- */

async function проверитьДваСтолаПодряд(исходникСети) {
  console.log('\n=== Б. Два стола подряд: заказ модуля живёт один вызов ===');
  const стр = поднятьСтраницу(исходникСети, 'нарды', ЛОББИ_НАРД);
  стр.рез.окно.настройкиСтолаПроверки = { контрольШахмат: '5+3' };
  await стр.рез.окно.ОнлайнЛобби.создатьСтол();
  await подождать();
  сравнить(последнееТело(стр, 'первый стол через модуль', 1),
    ожидаемое({ игра: 'нарды', мест: 2, компанией: true, открытый: true, контрольШахмат: '5+3' }), 'первый стол через модуль');

  // Второй — старой дорожкой (как шаги/«Создать новый стол»): тела модуля нет вовсе.
  await стр.рез.окно.Сеть.создатьКомнату({});
  await подождать();
  сравнить(последнееТело(стр, 'второй стол старой дорожкой', 2),
    ожидаемое({ игра: 'нарды' }), 'второй стол старой дорожкой — без настроек первого');

  // Третий — снова через модуль, но уже без настроек: контрольШахмат не прилип.
  стр.рез.окно.настройкиСтолаПроверки = {};
  await стр.рез.окно.ОнлайнЛобби.создатьСтол();
  await подождать();
  сравнить(последнееТело(стр, 'третий стол через модуль без настроек', 3),
    ожидаемое({ игра: 'нарды', мест: 2, компанией: true, открытый: true }), 'третий стол через модуль — без настроек первого');
}

/* ---------------------------------------------------------------------
   В. Дурак с модулем, как в index.html: старые дорожки — как на HEAD
   --------------------------------------------------------------------- */

const ЛОББИ_ДУРАКА = { игра: 'дурак', мест: { мин: 2, макс: 6, обычно: 2 }, создание: 'экран-друга' };

async function проверитьДуракаСМодулем(исходникСети) {
  console.log('\n=== В. Дурак с модулем (как index.html): старые дорожки не меняются ===');

  // Шаги дурака (игры/дурак/дурак-путь.js) — Сеть.создатьКомнату с лимитом хода.
  {
    const стр = поднятьСтраницу(исходникСети, 'дурак', ЛОББИ_ДУРАКА);
    await стр.рез.окно.Сеть.создатьКомнату({ мест: 3, переводной: true, компанией: true, открытый: true, лимитСекундНаХод: 30 });
    await подождать();
    сравнить(последнееТело(стр, 'шаги дурака', 1),
      ожидаемое({ игра: 'дурак', открытый: true, мест: 3, переводной: true, парами: false }), 'шаги дурака — как на HEAD');
  }

  // Шаги дурака на двоих, не открытый.
  {
    const стр = поднятьСтраницу(исходникСети, 'дурак', ЛОББИ_ДУРАКА);
    await стр.рез.окно.Сеть.создатьКомнату({ мест: 2, компанией: true, лимитСекундНаХод: 30 });
    await подождать();
    сравнить(последнееТело(стр, 'шаги дурака на двоих', 1),
      ожидаемое({ игра: 'дурак', мест: 2, переводной: false, парами: false }), 'шаги дурака на двоих — как на HEAD');
  }

  // Кнопка «Создать игру» на экране «Игра с другом».
  {
    const стр = поднятьСтраницу(исходникСети, 'дурак', ЛОББИ_ДУРАКА);
    стр.кнопкаСоздать.click();
    await подождать();
    await подождать();
    сравнить(последнееТело(стр, '«Игра с другом» → «Создать игру»', 1),
      ожидаемое({ игра: 'дурак' }), '«Игра с другом» → «Создать игру» — как на HEAD');
  }

  // «Создать открытый стол» с экрана «Найти игру».
  {
    const стр = поднятьСтраницу(исходникСети, 'дурак', ЛОББИ_ДУРАКА);
    await стр.рез.окно.Сеть.создатьОткрытыйСтол();
    await подождать();
    сравнить(последнееТело(стр, '«Создать открытый стол»', 1),
      ожидаемое({ игра: 'дурак', открытый: true }), '«Создать открытый стол» — как на HEAD');
  }
}

/* ---------------------------------------------------------------------
   Г. Без модуля — как было
   --------------------------------------------------------------------- */

async function проверитьБезМодуля(исходникСети) {
  console.log('\n=== Г. Без модуля — тело как было ===');
  const случаи = [
    { имя: 'нарды, пустой стол', игра: 'нарды', стол: {},
      ждём: ожидаемое({ игра: 'нарды' }) },
    { имя: 'нарды «компанией» открытый', игра: 'нарды', стол: { мест: 2, компанией: true, открытый: true, контрольШахмат: '5+3' },
      ждём: ожидаемое({ игра: 'нарды', открытый: true, мест: 2, переводной: false, парами: false }) },
    { имя: 'дурак на троих переводной', игра: 'дурак', стол: { мест: 3, переводной: true, компанией: true },
      ждём: ожидаемое({ игра: 'дурак', мест: 3, переводной: true, парами: false }) },
    { имя: 'нарды, модуль подключён для шашек (чужой)', игра: 'нарды', чужойМодуль: 'шашки', стол: {},
      ждём: ожидаемое({ игра: 'нарды' }) }
  ];
  for (const случай of случаи) {
    const стр = случай.чужойМодуль
      ? поднятьСтраницу(исходникСети, случай.игра, { игра: случай.чужойМодуль, мест: { мин: 2, макс: 2, обычно: 2 } })
      : поднятьСтраницу(исходникСети, случай.игра, false);
    const итог = await стр.рез.окно.Сеть.создатьКомнату(случай.стол);
    await подождать();
    проверить(итог && итог.ок === true, случай.имя + ': создатьКомнату ответил ок');
    сравнить(последнееТело(стр, случай.имя, 1), случай.ждём, случай.имя);
  }
}

/* ---------------------------------------------------------------------
   Д. Шахматы: метка shahmaty ↔ 'шахматы'
   --------------------------------------------------------------------- */

async function проверитьШахматы(исходникСети) {
  console.log('\n=== Д. Шахматы: метка shahmaty ↔ «шахматы» ===');
  const стр = поднятьСтраницу(исходникСети, 'шахматы', false);
  await стр.рез.окно.Сеть.создатьКомнату({});
  await подождать();
  const тело = последнееТело(стр, 'шахматы', 1);
  проверить(тело.игра === 'шахматы', 'страница шахмат шлёт игра:«шахматы» (получили ' + тело.игра + ')');
  проверить(стр.память.getItem('room_shahmaty') !== null, 'стол шахмат сохранён под ключом room_shahmaty');

  // Метка → игра: главная по ссылке shahmaty_КОД понимает, что звали в шахматы, —
  // по этому слову index.html перебрасывает на шахматы.html.
  const главная = поднятьСтраницу(исходникСети, 'дурак', false,
    { initDataUnsafe: { user: { first_name: ИМЯ }, start_param: 'shahmaty_QWERTY' } });
  const куда = главная.рез.окно.Сеть.какуюИгруПроситСсылка();
  проверить(куда === 'шахматы', 'ссылка shahmaty_QWERTY читается как «шахматы» (получили «' + куда + '»)');
}

/* ---------------------------------------------------------------------
   Главное
   --------------------------------------------------------------------- */

async function главное() {
  const копия = путьЛомающейКопии();
  const путьСети = копия || path.join(КОРЕНЬ, 'общее', 'js', 'сеть.js');
  if (копия) console.log('*** ЛОМАЮЩИЙ ЗАПУСК: копия ' + копия + ' — проверка обязана покраснеть. ***');
  console.log('  сеть.js: ' + путьСети);
  try {
    const исходникСети = fs.readFileSync(путьСети, 'utf8');
    await проверитьСМодулем(исходникСети);
    await проверитьДваСтолаПодряд(исходникСети);
    await проверитьДуракаСМодулем(исходникСети);
    await проверитьБезМодуля(исходникСети);
    await проверитьШахматы(исходникСети);
  } catch (сбой) {
    проверить(false, 'проверка упала — ' + (сбой && сбой.stack || сбой));
  }
  const провалы = проверки.filter(function (п) { return !п.ок; });
  console.log('\nИтого проверок: ' + проверки.length + ', провалов: ' + провалы.length);
  process.exit(провалы.length || проверки.length === 0 ? 1 : 0);
}

главное();
