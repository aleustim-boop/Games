  надо(п.рассадка().map((м) => м.роль).join() === 'я,соперник,напарник,соперник', 'напарник сидит напротив: ' + п.рассадка().map((м) => м.роль).join());
  надо(п.выбратьФормат('каждый').ок === true && п.выбор().игроков === 5, 'вернулись к «каждый за себя» — снова пятеро, как было');
