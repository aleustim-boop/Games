const fs = require('fs');
const path = require('path');
const КОРЕНЬ = path.join(__dirname, '..');
const ДуракПуть = require(path.join(КОРЕНЬ, 'js', 'дурак-путь.js'));
const правила = require(path.join(КОРЕНЬ, 'js', 'game.js'));

let провалов = 0;
function надо(условие, слова) {
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}

/** Память в Node: словарь с тем же видом дверей, что у js/game.js. */
function памятьИз(начало) {
  const склад = Object.assign({}, начало || {});
  return {
    склад: склад,
    прочитать: function (ключ) { return Object.prototype.hasOwnProperty.call(склад, ключ) ? склад[ключ] : ''; },
    записать: function (ключ, значение) { склад[ключ] = String(значение); }
  };
}

function путь(память, своиПравила) {
  return ДуракПуть.создать({ правила: своиПравила || правила, память: память || памятьИз() });
}

