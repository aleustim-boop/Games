  надо(числа.filter((ч) => ч.доступно).map((ч) => ч.число).join() === String(мест) &&
       числа.filter((ч) => !ч.доступно).every((ч) => /ровно/.test(ч.почему)),
    'остальные числа выключены и объяснены: «' + числа[0].почему + '»');
  const отказ = п.выбратьИгроков(6);
  надо(!отказ.ок && /Каждый за себя/.test(отказ.причина), '«6» при «2 на 2» — отказ словами');
