/* =====================================================================
   КАРТА ВХОДОВ В РЕЙТИНГ (шаг 6 плана «рейтинг по макету»).

   Решение владельца: «Общий рейтинг = сумма очков по всем играм».
   Разработчик развёл двери: общая функция «открытьРейтингИгроков(игра)»
   зовёт window.ЭкранРейтинга.открыть(игра), а над ней — две тонкие
   обёртки: «открытьОбщийРейтинг()» (даёт 'все') и «открытьРейтингДурака()»
   (даёт 'дурак'). Раньше ВСЕ двери звали одну функцию без параметра, и
   вкладка витрины открывала рейтинг игры, в которую играли последней, —
   это и была поломка.

   ЧТО ПРОВЕРЯЕТ ЭТОТ ФАЙЛ. Поднимает НАСТОЯЩИЙ js/game.js (и отдельно
   js/нижние-вкладки.js) в песочнице vm с поддельным DOM — приём взят
   из tests/подсказки-по-фазам.js (весь js/game.js целиком через
   vm.runInContext) и tests/проверка-нижних-вкладок.js (свой поддельный
   DOM для js/нижние-вкладки.js). window.ЭкранРейтинга здесь подложный:
   вместо показа экрана он просто ЗАПОМИНАЕТ, с каким именем игры его
   позвали. Дальше по очереди «нажимаются» все двери из карты:

     Откуда                                   | Узел                        | Игра
     ------------------------------------------|-----------------------------|--------
     Витрина, нижняя вкладка «Рейтинг»          | кнопка-вкладка-профиль      | 'все'
     Витрина, строка «Рейтинг» в листе «⋯»      | кнопка-лист-рейтинг         | 'все'
     Лобби дурака, вкладка «Рейтинг» (запасной  | лобби-вкладка-рейтинг       | 'дурак'
       вход, когда js/дурак-путь.js не грузится)|                             |
     Лобби дурака через дверь пути              | открытьРейтинг в конфиге,   | 'дурак'
       (задание называет это «ДуракЛобби.       | который game.js передаёт    |
       открытьРейтинг» — в реальном коде такого | в window.ДуракПуть.         |
       свойства у window.ДуракЛобби НЕТ, дверь  | подключить(...)             |
       лежит в другом месте, см. проверку ниже) |                             |
     Лобби шашек / шахмат / нард                | js/нижние-вкладки.js,       | 'шашки' /
                                                 | действия рейтинг-шашки/     | 'шахматы' /
                                                 | рейтинг-шахматы/рейтинг-нарды| 'нарды'
     Экран «Рекорды» дурака, «Рейтинг игроков»  | кнопкаРейтингаИгроков       | 'дурак'

   Отдельно проверяется, что window.ЭкранРейтинга.открыть ни разу не
   позван с undefined — это прямое следствие правки (функция теперь ждёт
   параметр).

   Запуск:
       node tests/карта-входов-в-рейтинг.js             — чистый прогон
       node tests/карта-входов-в-рейтинг.js --сломать   — ломающий прогон:
         портит КОПИЮ js/game.js (настоящий файл не трогает ни на секунду)
         так, что витрина снова открывает рейтинг «дурак» вместо общего
         «все» (имитация старой поломки «рейтинг последней игры»), гоняет
         те же проверки по копии и требует, чтобы нужные две проверки
         покраснели. Не покраснели — тест сам себя объявляет слепым.
   ===================================================================== */

