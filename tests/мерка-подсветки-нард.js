/* =====================================================================
   НАРДЫ — МЕРКА ПОДСВЕТКИ. Видно ли, куда можно пойти и чем.

   Запуск:
       node tests/мерка-подсветки-нард.js              — померить
       node tests/мерка-подсветки-нард.js --краснеет   — проверить мерку

   ---------------------------------------------------------------------
   ЗАЧЕМ. Цвет подсветки в сборнике общий для всех игр, и когда его
   меняют, каждую доску надо перемерить заново. Глазами это делать
   нельзя: «вроде видно» у зрячего человека и у того, кто путает красное
   с зелёным, — разные вещи. Меряем числом: обычным отношением яркостей,
   порог 3,0, тот же, что держат в шашках.

   ---------------------------------------------------------------------
   ГЛАВНЫЙ УРОК, РАДИ КОТОРОГО ЭТА МЕРКА ПЕРЕПИСАНА.

   Сперва она считала только ЗАЛИВКУ — светлую краску поверх пункта.
   Потом подсветку починили иначе: добавили ТЁМНЫЙ КОНТУР по краю.
   Мерка про контур не знала и продолжала показывать прежние числа,
   то есть честно докладывала «не починено» про починенное.

   За один день в это попали дважды — здесь и в шахматах. Отсюда
   правило: КОГДА МЕНЯЕТСЯ ПРИЁМ, А НЕ ЧИСЛО, ПРОВЕРКУ ОБНОВЛЯЮТ ВМЕСТЕ
   С ПРАВКОЙ. Иначе она будет врать в удобную сторону — «красное»,
   которому перестают верить, ничем не лучше ложного «зелёного».

   Поэтому здесь мерка не хранит своего представления об устройстве
   подсветки. Она ЧИТАЕТ ИЗ style-нарды.css и цвета, и слои: сколько
   краски в заливке, какой густоты тёмные линии, где они лежат. Появится
   третий слой — она увидит и его, а не промолчит.

   ---------------------------------------------------------------------
   КАК СЧИТАЕМ. У подсветки несколько слоёв, и порог обязан взять ХОТЯ БЫ
   ОДИН. Требовать от всех неверно: на тёмном пункте вытягивает светлая
   заливка, на светлом — тёмный контур, и наоборот они не работают по
   устройству.

   Размытые тени за слой не считаются: слой — это чёткая линия, по
   которой глаз ловит границу, а размытая тень границы не даёт.
   ===================================================================== */

const fs = require('fs');
const path = require('path');

const стиль = fs.readFileSync(path.join(__dirname, '..', 'style-нарды.css'), 'utf8');
const ПОРОГ = 3.0;
const ДОСКИ = ['дерево', 'камень', 'классика'];
const ПРОВЕРИТЬ_МЕРКУ = process.argv.indexOf('--краснеет') !== -1;

/* =====================================================================
   ЦВЕТ И ЯРКОСТЬ
   ===================================================================== */

function разобратьЦвет(текст) {
  const части = /^#?([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i.exec(String(текст).trim());
  if (!части) throw new Error('Не понимаю цвет: ' + текст);
  return [parseInt(части[1], 16), parseInt(части[2], 16), parseInt(части[3], 16)];
}

function яркость(цвет) {
  const канал = function (значение) {
    const доля = значение / 255;
    return доля <= 0.03928 ? доля / 12.92 : Math.pow((доля + 0.055) / 1.055, 2.4);
  };
  return 0.2126 * канал(цвет[0]) + 0.7152 * канал(цвет[1]) + 0.0722 * канал(цвет[2]);
}

function отношение(а, б) {
  const пара = [яркость(а), яркость(б)].sort(function (х, у) { return у - х; });
  return (пара[0] + 0.05) / (пара[1] + 0.05);
}

/** Полупрозрачный слой поверх — то, что глаз видит на самом деле. */
function смешать(верх, низ, доля) {
  return [0, 1, 2].map(function (i) { return Math.round(верх[i] * доля + низ[i] * (1 - доля)); });
}

function тёмный(цвет) { return цвет[0] < 90 && цвет[1] < 90 && цвет[2] < 90; }

/* =====================================================================
   ЧТЕНИЕ УСТРОЙСТВА ИЗ ОФОРМЛЕНИЯ
   ===================================================================== */

function телоПравила(искомое) {
  const найдено = new RegExp(искомое.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\s*\\{([\\s\\S]*?)\\}')
    .exec(стиль);
  return найдено ? найдено[1] : null;
}

function телоДоски(имя) {
  const правило = имя === 'дерево'
    ? /html,\s*html\[data-доска="дерево"\]\s*\{([\s\S]*?)\}/.exec(стиль)
    : new RegExp('html\\[data-доска="' + имя + '"\\]\\s*\\{([\\s\\S]*?)\\}').exec(стиль);
  if (!правило) throw new Error('В оформлении нет доски «' + имя + '»');
  return правило[1];
}

function переменная(тело, имя) {
  const найдено = new RegExp('--' + имя + '\\s*:\\s*(#[0-9a-fA-F]{6})').exec(тело);
  if (!найдено) throw new Error('У доски нет переменной --' + имя);
  return разобратьЦвет(найдено[1]);
}

/** Разделить список через запятую, не разрезая rgba( … ). */
function поЗапятым(текст) {
  const куски = [];
  let глубина = 0;
  let текущий = '';
  for (const знак of текст) {
    if (знак === '(') глубина++;
    if (знак === ')') глубина--;
    if (знак === ',' && глубина === 0) { куски.push(текущий); текущий = ''; continue; }
    текущий += знак;
  }
  if (текущий.trim()) куски.push(текущий);
  return куски.map(function (к) { return к.trim(); }).filter(Boolean);
}

/**
 * Слои подсвеченного ПУНКТА: светлая заливка и тёмный контур.
 * Контур сделан четырьмя тенями по сторонам — обычной рамкой треугольник
 * не обвести, она обрезалась бы вместе с его углами. Все четыре одного
 * цвета, поэтому берём первую.
 */
function слоиПункта(имяДоски, подсветка) {
  const общее = телоПравила('.пункт--можно::after');
  const своё = телоПравила('html[data-доска="' + имяДоски + '"] .пункт--можно::after');
  const слои = [];

  function заливка(тело) {
    const найдено = /color-mix\([^)]*var\(--подсветка\)\s*(\d+)%/.exec(тело);
    return найдено ? Number(найдено[1]) / 100 : null;
  }
  function контур(тело) {
    const найдено = /drop-shadow\([^)]*rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.]+)\s*\)/.exec(тело);
    if (!найдено) return null;
    const цвет = [Number(найдено[1]), Number(найдено[2]), Number(найдено[3])];
    return тёмный(цвет) ? { цвет: цвет, густота: Number(найдено[4]) } : null;
  }

  const густотаЗаливки = (своё && заливка(своё)) || (общее && заливка(общее));
  if (!густотаЗаливки) throw new Error('Не нашёл, с какой густотой заливается подсвеченный пункт');
  слои.push({ имя: 'заливка ' + Math.round(густотаЗаливки * 100) + '%', цвет: подсветка, густота: густотаЗаливки, тёмный: false });

  const обводка = (своё && контур(своё)) || (общее && контур(общее));
  if (обводка) {
    слои.push({ имя: 'контур ' + Math.round(обводка.густота * 100) + '%', цвет: обводка.цвет, густота: обводка.густота, тёмный: true });
  }
  return слои;
}

/**
 * Слои КОЛЬЦА вокруг шашки. Это набор теней: золотое кольцо и тёмные
 * линии по обе стороны от него. Размытые тени пропускаем — они не дают
 * чёткой границы, а значит и не помогают увидеть кольцо.
 */
function слоиКольца(имяПравила, подсветка) {
  const тело = телоПравила(имяПравила);
  if (!тело) return [];
  const строка = /box-shadow:\s*([\s\S]*?);/.exec(тело);
  if (!строка) return [];
  const слои = [];
  for (const тень of поЗапятым(строка[1])) {
    const доЦвета = тень.replace(/(rgba?|var)\([^)]*\)/g, '').trim();
    const числа = доЦвета.split(/\s+/).filter(function (т) { return /[\d.]/.test(т); });
    const размытие = числа.length >= 3 ? parseFloat(числа[2]) : 0;
    if (размытие > 0) continue;                       // размытая тень — не линия
    if (тень.indexOf('var(--подсветка)') !== -1) {
      слои.push({ имя: 'золото', цвет: подсветка, густота: 1, тёмный: false });
      continue;
    }
    const цветТени = /rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.]+)\s*\)/.exec(тень);
    if (!цветТени) continue;
    const цвет = [Number(цветТени[1]), Number(цветТени[2]), Number(цветТени[3])];
    if (!тёмный(цвет)) continue;
    слои.push({
      имя: (тень.indexOf('inset') !== -1 ? 'тёмная линия внутри ' : 'тёмная линия снаружи ') +
        Math.round(Number(цветТени[4]) * 100) + '%',
      цвет: цвет, густота: Number(цветТени[4]), тёмный: true
    });
  }
  return слои;
}

/* =====================================================================
   СЧЁТ
   ===================================================================== */

/**
 * Лучшее, что даёт подсветка на этом фоне. «безТёмных» нужен запуску
 * «--краснеет»: он мысленно стирает тёмные слои, и числа обязаны упасть.
 */
function лучшийСлой(слои, фон, безТёмных) {
  let лучшее = { отношение: 0, имя: 'ничего' };
  for (const слой of слои) {
    if (безТёмных && слой.тёмный) continue;
    const видно = отношение(смешать(слой.цвет, фон, слой.густота), фон);
    if (видно > лучшее.отношение) лучшее = { отношение: видно, имя: слой.имя };
  }
  return лучшее;
}

/** Все пары, которые надо померить. Собираются из оформления. */
function собратьПары() {
  const пары = [];
  for (const имя of ДОСКИ) {
    const тело = телоДоски(имя);
    const подсветка = переменная(тело, 'подсветка');
    const пункты = слоиПункта(имя, подсветка);
    for (const вид of ['тёмный', 'светлый']) {
      пары.push({
        раздел: 'пункт',
        название: имя + ', ' + вид + ' пункт',
        слои: пункты,
        фон: переменная(тело, 'пункт-' + вид)
      });
    }
    const кольцо = слоиКольца('.шашка--можно-взять', подсветка);
    for (const чья of ['белая', 'чёрная']) {
      пары.push({
        раздел: 'кольцо',
        название: имя + ', ' + чья + ' шашка — можно взять',
        слои: кольцо,
        фон: переменная(тело, 'шашка-' + чья)
      });
    }
    const поднята = слоиКольца('.шашка--поднята', подсветка);
    for (const чья of ['белая', 'чёрная']) {
      пары.push({
        раздел: 'поднята',
        название: имя + ', ' + чья + ' шашка — поднята',
        слои: поднята,
        фон: переменная(тело, 'шашка-' + чья)
      });
    }
  }
  return пары;
}

/* Раскладываем по разделам, а не по доскам: сравнивать надо однородное,
   иначе три одинаковых заголовка идут вперемешку и глаз не собирает
   картину. */
const ПОРЯДОК_РАЗДЕЛОВ = ['пункт', 'кольцо', 'поднята'];
const пары = собратьПары().sort(function (а, б) {
  return ПОРЯДОК_РАЗДЕЛОВ.indexOf(а.раздел) - ПОРЯДОК_РАЗДЕЛОВ.indexOf(б.раздел);
});

/* =====================================================================
   ЗАПУСК «--КРАСНЕЕТ»: а видит ли мерка тёмные слои вообще

   Проверка, которая не умеет покраснеть, — обман. Здесь мы мысленно
   стираем все тёмные слои и требуем, чтобы там, где именно они держат
   порог, числа упали. Если не упали — мерка их не читает, и всем её
   зелёным числам грош цена.
   ===================================================================== */

if (ПРОВЕРИТЬ_МЕРКУ) {
  console.log('=== Проверяем саму мерку: видит ли она тёмные слои ===\n');
  let держатТёмные = 0;
  let плохо = 0;
  for (const пара of пары) {
    const сТёмными = лучшийСлой(пара.слои, пара.фон, false);
    if (!/контур|тёмная/.test(сТёмными.имя)) continue;   // здесь тянет не тёмный слой
    держатТёмные++;
    const безТёмных = лучшийСлой(пара.слои, пара.фон, true);
    const упало = безТёмных.отношение < сТёмными.отношение - 0.5;
    if (!упало) плохо++;
    console.log('  ' + (упало ? 'ок    ' : 'ПЛОХО ') + пара.название + ': с тёмным слоем ' +
      сТёмными.отношение.toFixed(2) + ', без него ' + безТёмных.отношение.toFixed(2));
  }
  if (!держатТёмные) {
    console.log('  ПЛОХО ни одну пару не держит тёмный слой — мерка их не видит вовсе');
    плохо++;
  }
  console.log('\nПар, которые держит тёмный слой: ' + держатТёмные + ', из них не покраснело ' + плохо);
  process.exitCode = плохо ? 1 : 0;
} else {

  /* =====================================================================
     ОБЫЧНЫЙ ЗАПУСК
     ===================================================================== */

  let всего = 0;
  let плохо = 0;
  let разделСейчас = null;
  const ЗАГОЛОВКИ = {
    'пункт': 'КУДА МОЖНО ПОЙТИ: подсвеченный пункт против такого же неподсвеченного',
    'кольцо': 'ЧЕМ МОЖНО ПОЙТИ: кольцо вокруг шашки против самой шашки',
    'поднята': 'ПОДНЯТАЯ ШАШКА: то же кольцо, когда шашку уже взяли'
  };

  console.log('=== Нарды: видно ли подсветку. Порог ' + ПОРОГ.toFixed(1) + ' ===');
  console.log('Слои и густоты прочитаны из style-нарды.css, а не записаны здесь.\n');

  for (const пара of пары) {
    if (пара.раздел !== разделСейчас) {
      разделСейчас = пара.раздел;
      console.log('\n' + ЗАГОЛОВКИ[разделСейчас]);
    }
    всего++;
    const лучшее = лучшийСлой(пара.слои, пара.фон, false);
    const прошло = лучшее.отношение >= ПОРОГ;
    if (!прошло) плохо++;
    console.log('  ' + (прошло ? 'ок    ' : 'ПЛОХО ') + пара.название + ': ' +
      лучшее.отношение.toFixed(2) + ' (тянет ' + лучшее.имя + ')' +
      (прошло ? '' : '  — не хватает ' + (ПОРОГ - лучшее.отношение).toFixed(2)));
  }

  /* Если что-то не проходит на светлой шашке — считаем, какой тёмной
     линии хватит. Приём тот же, что спас светлые пункты; печатаем число,
     чтобы оформителю не пришлось подбирать на глаз. */
  const советы = [];
  for (const пара of пары) {
    if (лучшийСлой(пара.слои, пара.фон, false).отношение >= ПОРОГ) continue;
    let нужно = null;
    for (let густота = 1; густота <= 100; густота++) {
      if (отношение(смешать([0, 0, 0], пара.фон, густота / 100), пара.фон) >= ПОРОГ) { нужно = густота; break; }
    }
    советы.push('  ' + пара.название + ': хватит тёмной линии от ' + нужно + '%');
  }
  if (советы.length) {
    console.log('\nЧТО СДЕЛАТЬ. Светлое на светлом не даёт трёхкратной разницы ни');
    console.log('при какой густоте — другим цветом это не лечится. Спасает тёмная');
    console.log('линия, тот же приём, что и на светлых пунктах:');
    console.log(советы.join('\n'));
  }

  console.log('\nИтого: ' + всего + ' пар, не прошло ' + плохо);
  console.log('Проверить саму мерку:  node tests/мерка-подсветки-нард.js --краснеет');
  if (плохо) process.exitCode = 1;
}
