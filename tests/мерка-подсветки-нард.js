/* =====================================================================
   НАРДЫ — МЕРКА ПОДСВЕТКИ. Видно ли, куда можно пойти.

   Запуск:  node tests/мерка-подсветки-нард.js

   ЗАЧЕМ. Цвет подсветки в сборнике общий для всех игр, и когда его
   меняют, каждую доску надо перемерить заново. Глазами это делать
   нельзя: «вроде видно» у зрячего человека и у того, кто путает красное
   с зелёным, — разные вещи. Меряем числом.

   ЧЕМ МЕРЯЕМ. Обычное отношение яркостей (то самое, из правил
   доступности): у двух цветов считается яркость, и берётся отношение
   светлого к тёмному с поправкой 0,05. Порог 3,0 — тот же, что держат
   в шашках.

   ЧТО ИМЕННО СРАВНИВАЕМ. Подсветка в нардах — не значок, а заливка
   всего треугольника поверх его цвета. Значит, сравнивать надо
   подсвеченный пункт с таким же НЕподсвеченным: человек должен увидеть,
   что этот треугольник изменился. Пунктов два вида, светлый и тёмный,
   досок три — отсюда шесть пар.

   Отдельно меряется кольцо вокруг шашки, которой можно пойти: оно
   рисуется тем же цветом и лежит на шашке, а шашки две — белая и
   чёрная. Эту пару сначала никто не мерил, и она оказалась хуже
   остальных: золото на кремовой шашке почти не видно.

   ЦВЕТА БЕРУТСЯ ИЗ style-нарды.css, а не переписаны сюда. Вторая копия
   цветов однажды разошлась бы с настоящей, и мерка мерила бы то, чего
   на экране нет.
   ===================================================================== */

const fs = require('fs');
const path = require('path');

const ФАЙЛ_ОФОРМЛЕНИЯ = path.join(__dirname, '..', 'style-нарды.css');
const ПОРОГ = 3.0;
const ДОСКИ = ['дерево', 'камень', 'классика'];

const стиль = fs.readFileSync(ФАЙЛ_ОФОРМЛЕНИЯ, 'utf8');

/* --------------------------------------------------------------- цвет */

function разобратьЦвет(текст) {
  const части = /^#?([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i.exec(String(текст).trim());
  if (!части) throw new Error('Не понимаю цвет: ' + текст);
  return [parseInt(части[1], 16), parseInt(части[2], 16), parseInt(части[3], 16)];
}

function яркость(цвет) {
  const канал = function (значение) {
    const доля = значение / 255;
    return доля <= 0.03928 ? доля / 12.92 : Math.pow((доля + 0.055) / 1.055, 2.4);
  };
  return 0.2126 * канал(цвет[0]) + 0.7152 * канал(цвет[1]) + 0.0722 * канал(цвет[2]);
}

function отношение(а, б) {
  const пара = [яркость(а), яркость(б)].sort(function (х, у) { return у - х; });
  return (пара[0] + 0.05) / (пара[1] + 0.05);
}

/** Полупрозрачный слой поверх — то, что глаз видит на самом деле. */
function смешать(верх, низ, доля) {
  return [0, 1, 2].map(function (i) { return Math.round(верх[i] * доля + низ[i] * (1 - доля)); });
}

/* ------------------------------------------------- чтение оформления */

/** Тело правила для одной доски: html[data-доска="камень"] { … } */
function телоДоски(имя) {
  const правило = имя === 'дерево'
    ? /html,\s*html\[data-доска="дерево"\]\s*\{([\s\S]*?)\}/.exec(стиль)
    : new RegExp('html\\[data-доска="' + имя + '"\\]\\s*\\{([\\s\\S]*?)\\}').exec(стиль);
  if (!правило) throw new Error('В оформлении нет доски «' + имя + '»');
  return правило[1];
}

function переменная(тело, имя) {
  const найдено = new RegExp('--' + имя + '\\s*:\\s*(#[0-9a-fA-F]{6})').exec(тело);
  if (!найдено) throw new Error('У доски нет переменной --' + имя);
  return разобратьЦвет(найдено[1]);
}

/**
 * Из чего состоит подсветка пункта. У каждой доски она может быть своя:
 * есть общее правило «.пункт--можно::after», а поверх него —
 * «html[data-доска="классика"] .пункт--можно::after» со своими числами.
 * Читаем сперва общее, потом накрываем particular-ым.
 *
 * Заливка задана не прозрачностью узла, а густотой в color-mix — это
 * разные вещи, и на этом мерка один раз уже ошиблась: приняла
 * «opacity: 1» за сплошную заливку и намерила ерунду.
 *
 * Контур сделан четырьмя тенями по сторонам, все одного цвета, — берём
 * первую попавшуюся, остальные ей равны.
 */
function частиПодсветки(имяДоски) {
  const общее = /\.пункт--можно::after\s*\{([\s\S]*?)\}/.exec(стиль);
  const своё = new RegExp('html\\[data-доска="' + имяДоски + '"\\]\\s*\\.пункт--можно::after\\s*\\{([\\s\\S]*?)\\}')
    .exec(стиль);

  function густотаЗаливки(тело) {
    const найдено = /color-mix\([^)]*var\(--подсветка\)\s*(\d+)%/.exec(тело);
    return найдено ? Number(найдено[1]) / 100 : null;
  }
  function контур(тело) {
    const найдено = /rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.]+)\s*\)/.exec(тело);
    if (!найдено) return null;
    if (Number(найдено[1]) > 90 || Number(найдено[2]) > 90 || Number(найдено[3]) > 90) return null;
    return {
      цвет: [Number(найдено[1]), Number(найдено[2]), Number(найдено[3])],
      густота: Number(найдено[4])
    };
  }

  const заливка = (своё && густотаЗаливки(своё[1])) || (общее && густотаЗаливки(общее[1]));
  const обводка = (своё && контур(своё[1])) || (общее && контур(общее[1]));
  if (!заливка) throw new Error('Не нашёл, с какой густотой заливается подсвеченный пункт');
  return { заливка: заливка, контур: обводка };
}

/* ------------------------------------------------------------ прогон */

let всего = 0;
let плохо = 0;

function проверить(название, отношениеЯркостей) {
  всего++;
  const прошло = отношениеЯркостей >= ПОРОГ;
  if (!прошло) плохо++;
  console.log('  ' + (прошло ? 'ок    ' : 'ПЛОХО ') + название + ': ' + отношениеЯркостей.toFixed(2) +
    (прошло ? '' : '  (не хватает ' + (ПОРОГ - отношениеЯркостей).toFixed(2) + ')'));
}

console.log('=== Нарды: видно ли, куда можно пойти. Порог ' + ПОРОГ.toFixed(1) + ' ===');
console.log('');
console.log('ГЛАВНОЕ ПРАВИЛО СЧЁТА. Подсветка состоит из двух частей — заливки');
console.log('и тёмного контура, — и порог обязана взять ХОТЯ БЫ ОДНА из них.');
console.log('Требовать обе неверно: на тёмном пункте вытягивает светлая');
console.log('заливка, на светлом — тёмный контур, и наоборот они не работают');
console.log('по устройству. Мерка сначала требовала обе и зря краснела.\n');

console.log('ШЕСТЬ ПАР: подсвеченный пункт против такого же неподсвеченного');
for (const имя of ДОСКИ) {
  const тело = телоДоски(имя);
  const подсветка = переменная(тело, 'подсветка');
  const части = частиПодсветки(имя);
  for (const вид of ['тёмный', 'светлый']) {
    const пункт = переменная(тело, 'пункт-' + вид);
    const отЗаливки = отношение(смешать(подсветка, пункт, части.заливка), пункт);
    const отКонтура = части.контур
      ? отношение(смешать(части.контур.цвет, пункт, части.контур.густота), пункт)
      : 0;
    const лучшее = Math.max(отЗаливки, отКонтура);
    const ктоТянет = отЗаливки >= отКонтура
      ? 'заливка ' + Math.round(части.заливка * 100) + '%'
      : 'контур ' + Math.round(части.контур.густота * 100) + '%';
    проверить(имя + ', ' + вид + ' пункт (тянет ' + ктоТянет + '; заливка ' +
      отЗаливки.toFixed(2) + ', контур ' + отКонтура.toFixed(2) + ')', лучшее);
  }
}

console.log('\nКОЛЬЦО ВОКРУГ ШАШКИ, КОТОРОЙ МОЖНО ПОЙТИ:');
for (const имя of ДОСКИ) {
  const тело = телоДоски(имя);
  const подсветка = переменная(тело, 'подсветка');
  for (const чья of ['белая', 'чёрная']) {
    проверить(имя + ', ' + чья + ' шашка', отношение(подсветка, переменная(тело, 'шашка-' + чья)));
  }
}

/* Если кольцо на светлой шашке не проходит — считаем, какой тёмный
   ободок его вытянет. Приём тот же, что спас светлые пункты: не менять
   цвет подсветки, а обвести её тёмным. Число печатаем сразу, чтобы
   оформителю не пришлось подбирать на глаз. */
const мало = [];
for (const имя of ДОСКИ) {
  const тело = телоДоски(имя);
  const белая = переменная(тело, 'шашка-белая');
  if (отношение(переменная(тело, 'подсветка'), белая) >= ПОРОГ) continue;
  let нужно = null;
  for (let густота = 1; густота <= 100; густота++) {
    if (отношение(смешать([0, 0, 0], белая, густота / 100), белая) >= ПОРОГ) { нужно = густота; break; }
  }
  мало.push('  ' + имя + ': тёмный ободок вокруг кольца от ' + нужно + '%');
}
if (мало.length) {
  console.log('\nЧТО ЭТО ЗНАЧИТ. Золотое кольцо на кремовой шашке не видно, и');
  console.log('другим цветом это не лечится: светлое на светлом не даёт');
  console.log('трёхкратной разницы. Спасёт тот же тёмный ободок, что и на');
  console.log('светлых пунктах. Сколько его нужно:');
  console.log(мало.join('\n'));
  console.log('Белых шашек ровно половина, поэтому место не мелкое.');
}

console.log('\nИтого: ' + всего + ' пар, не прошло ' + плохо);
if (плохо) process.exitCode = 1;
