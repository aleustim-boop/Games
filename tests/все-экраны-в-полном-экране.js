/* ---- ломающий флаг --сломать-шапку (только для проверки шапки рейтинга) ----
   Портит КОПИЮ style.css во временной папке (os.tmpdir()) — настоящий
   файл проекта эта проверка не трогает НИ НА СЕКУНДУ, правит только байты
   на диске в своей копии. Порча — переменная «--отступ-сверху» (правило
   у :root, style.css): она собирает безопасный отступ сверху из
   env(safe-area-inset-top) и телеграмной «--безопасно-сверху» и стоит в
   padding каждого служебного экрана, в том числе у шапки рейтинга.
   Обнуляем её в копии — шапка лишается отступа и обязана уйти под чужие
   часы Telegram; красной становится та же проверка «верх не под часами
   Telegram», что меряет любой другой экран стенда (функция «померить»),
   только теперь на экране «рейтинг игроков».
   Подмена — на уровне playwright: страница.route по regex
   /\/style\.css(?:\?|$)/ (страница просит «style.css?v=NN» — glob без
   хвоста «?v=» такое не ловит, ловит только regex), сервер отдаёт файлы
   проекта как есть, без спецкейсов. Ради экономии браузера в этом режиме
   НЕ гоняем весь тяжёлый обход трёх размеров и двух игр — только быстро
   доходим до вкладки «Рейтинг» лобби дурака на 390×844. */
