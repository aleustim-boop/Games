/* =====================================================================
   ВСЕ ЭКРАНЫ ОБЕИХ ИГР В ПОЛНОМ ЭКРАНЕ TELEGRAM.

   Зачем. В полном экране (Bot API 8.0) шапки Telegram нет, и поверх нашей
   страницы оказываются две чужие полосы: сверху часы телефона и кнопки
   Telegram («закрыть» и «…»), снизу — полоса жеста. Наша игра обязана
   держаться от них подальше. Один экран проверить легко, а их у двух игр
   почти два десятка, и уехать под часы может любой.

   Что делает стенд. Заходит на каждый экран НАСТОЯЩИМИ нажатиями (партии
   доигрывает сам) и меряет:
     • верх содержимого — не залез ли под верхнюю полосу;
     • низ содержимого — не ушёл ли под полосу жеста, а если ушёл,
       можно ли доехать прокруткой;
     • ширину — не вылезло ли что вбок.
   На каждый непорядок кладёт снимок в tests/скриншоты/.

   Полосы берём как на телефоне с вырезом: сверху 46 системных + 12
   телеграмных = 58 точек, снизу 34. Эти числа подделка Telegram отдаёт
   игре так же, как настоящий (tests/поддельный-телеграм.js).

   Запуск (страничный сервер уже поднят):
       node tests/все-экраны-в-полном-экране.js
       node tests/все-экраны-в-полном-экране.js 8080 8797
   Первое число — порт страниц, второе — свободный порт, на котором стенд
   сам поднимет сервер комнат «--без-памяти» (нужен, чтобы дойти до экрана
   комнаты по-настоящему). Сервер этот стенд гасит за собой сам.
   ===================================================================== */

