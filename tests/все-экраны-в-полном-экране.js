/**
 * Померить видимый экран и сказать, не залез ли он под чужие полосы.
 * «имя» — как экран зовут люди, оно попадёт в отчёт и в имя снимка.
 */
async function померить(страница, имя, размер) {
  const мера = await страница.evaluate(() => {
    /* Берём ПОСЛЕДНИЙ видимый экран: плашки итога и выхода показываются
       поверх стола, и «виден» помечены оба — первый не тот, что смотрит игрок. */
    const видимые = document.querySelectorAll('.экран.экран--виден');
    const экран = видимые[видимые.length - 1];
    if (!экран) return null;
    const листья = [];
    экран.querySelectorAll('*').forEach((у) => {
      if (у.children.length) return;                   // меряем только листья: текст, кнопки, карты
      const к = у.getBoundingClientRect();
      if (к.width < 2 || к.height < 2) return;
      const с = getComputedStyle(у);
      if (с.visibility === 'hidden' || с.display === 'none' || Number(с.opacity) === 0) return;
      const примета = String(у.textContent || у.id || (у.className && у.className.baseVal) || у.tagName || '');
      листья.push({ верх: Math.round(к.top), низ: Math.round(к.bottom), что: примета.trim().slice(0, 26), узел: у });
    });
    if (!листья.length) return { экран: экран.id, пусто: true };
    листья.sort((а, б) => а.верх - б.верх);
    const нижний = листья.slice().sort((а, б) => б.низ - а.низ)[0];

    /* Прокрутка бывает не только у самого экрана: на «Как играть» крутится
       внутренний список правил. Поэтому ищем прокрутку и у него, и у всех
       его родителей до экрана — иначе стенд объявил бы поломкой текст,
       до которого палец прекрасно доезжает. */
    let запасПрокрутки = Math.max(0, экран.scrollHeight - экран.clientHeight);
    let узел = нижний.узел;
    while (узел && узел !== экран.parentElement) {
      запасПрокрутки = Math.max(запасПрокрутки, узел.scrollHeight - узел.clientHeight);
      узел = узел.parentElement;
    }

    return {
      экран: экран.id,
      всегоЭкранов: видимые.length,
      верхний: { верх: листья[0].верх, низ: листья[0].низ, что: листья[0].что },
      нижний: { верх: нижний.верх, низ: нижний.низ, что: нижний.что },
      можноПрокрутить: Math.max(0, запасПрокрутки),
      ширина: document.documentElement.scrollWidth,
      окно: window.innerWidth
    };
  });

  if (!мера) { проверить(false, имя + ': видимого экрана не нашлось'); return; }
  if (мера.пусто) { console.log('    (' + имя + ' [' + мера.экран + ']: показывать нечего — пустой экран, пропускаю)'); return; }

  console.log('    ' + имя + ' [' + мера.экран + ']: верх ' + мера.верхний.верх + 'px «' + мера.верхний.что +
    '», низ ' + мера.нижний.низ + 'px «' + мера.нижний.что + '»');

  const граница = размер.в - ЗАПРЕТ_СНИЗУ;
  const верхОК = мера.верхний.верх >= ЗАПРЕТ_СВЕРХУ;
  const низВлез = мера.нижний.низ <= граница;
  /* Сколько у нижней части осталось над полосой жеста. Кнопка, которая
     нарочно уходит вниз под полосу, но держит надпись выше неё, — это
     нормальная нижняя плашка, а не поломка: пальцу есть куда попасть.
     Плохо, только когда над полосой не осталось ничего и прокрутки нет. */
  const доступноНадПолосой = граница - мера.нижний.верх;
  const низОК = низВлез || доступноНадПолосой >= 24 || мера.можноПрокрутить > 0;

  проверить(верхОК, имя + ': верх не под часами Telegram (' + мера.верхний.верх + ' ≥ ' + ЗАПРЕТ_СВЕРХУ + ')');
  проверить(низОК, имя + ': низ достижим (низ ' + мера.нижний.низ + ' при пределе ' + граница +
    ', над полосой осталось ' + Math.max(0, доступноНадПолосой) + 'px, прокрутка ' + мера.можноПрокрутить + 'px)');
  проверить(мера.ширина <= мера.окно, имя + ': вбок ничего не вылезло (' + мера.ширина + ' ≤ ' + мера.окно + ')');

  if (низОК && !низВлез) {
    замечаний++;
    console.log('      (замечание: «' + мера.нижний.что + '» уходит под полосу жеста на ' +
      (мера.нижний.низ - граница) + 'px; над полосой осталось ' + Math.max(0, доступноНадПолосой) +
      'px, прокрутка ' + мера.можноПрокрутить + 'px)');
  }
  if (!верхОК || !низОК || мера.ширина > мера.окно) {
    const файл = ПАПКА_СНИМКОВ + 'полный-экран-' + размер.ш + '-' + мера.экран + '.png';
    await страница.screenshot({ path: файл });
    console.log('      снимок: ' + файл);
  }
}

