const спать = (мс) => new Promise((ф) => setTimeout(ф, мс));

/** Нажать, если кнопка есть и видна. Нужно там, где путь стал короче:
    «Играть с ботом» теперь ведёт сразу за стол, и отдельной кнопки
    «Играть» на дороге может не быть вовсе. */
/**
 * Дождаться, пока кнопка станет видна, и нажать. Пауз по часам тут мало:
 * экран меняется не мгновенно, и на занятой машине «поспать 300 мс»
 * иногда кончается раньше, чем появляется кнопка. Тогда playwright ждёт
 * невидимый узел тридцать секунд и роняет весь стенд — вместе со всеми
 * замерами, которые шли следом.
 */
async function нажатьКогдаВидна(страница, примета, потолокМс) {
  const начало = Date.now();
  while (Date.now() - начало < (потолокМс || 8000)) {
    const видна = await страница.evaluate((п) => {
      const к = document.querySelector(п);
      return Boolean(к && к.offsetParent !== null);
    }, примета);
    if (видна) { await страница.click(примета, { timeout: 4000 }); return true; }
    await спать(50);
  }
  console.log('    (кнопку ' + примета + ' так и не дождались за ' + (потолокМс || 8000) + ' мс)');
  return false;
}

/**
 * Шаг «назад», как его делает человек. С 11 сентября внутри Telegram
 * оформление прячет кнопки «‹» на «Как играть», «Рекордах» и «Оформлении»:
 * там уходят стрелкой «Назад» самого Telegram. Стенд ждал спрятанную
 * кнопку, не дожидался — и оставался на правилах: все следующие шаги
 * мерили не тот экран. Теперь: видна кнопка — жмём её, нет — стрелку.
 */
async function назадКакЧеловек(страница, примета) {
  const начало = Date.now();
  while (Date.now() - начало < 1500) {
    const видна = await страница.evaluate((п) => {
      const к = document.querySelector(п);
      return Boolean(к && к.offsetParent !== null);
    }, примета);
    if (видна) { await страница.click(примета, { timeout: 4000 }); return 'кнопкой'; }
    await спать(50);
  }
  const стрелка = await страница.evaluate(() => {
    const в = window.Telegram && window.Telegram.WebApp;
    if (!в || !в.BackButton || !в.BackButton.isVisible || !window.ПоддельныйТелеграм) return false;
    window.ПоддельныйТелеграм.нажатьНазад();
    return true;
  });
  if (!стрелка) console.log('    (ни кнопки ' + примета + ', ни стрелки Telegram — назад уйти нечем)');
  return стрелка ? 'стрелкой Telegram' : 'никак';
}

async function нажатьЕслиЕсть(страница, примета) {
  try {
    const видна = await страница.evaluate((п) => {
      const к = document.querySelector(п);
      return !!(к && к.offsetParent !== null);
    }, примета);
    if (!видна) return false;
    await страница.click(примета, { timeout: 4000 });
    return true;
  } catch (сбой) { return false; }
}

