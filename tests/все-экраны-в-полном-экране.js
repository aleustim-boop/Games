function портЗанят(порт) {
  return new Promise(function (готово) {
    const гнездо = net.connect({ host: '127.0.0.1', port: порт });
    const конец = (ответ) => { гнездо.destroy(); готово(ответ); };
    гнездо.setTimeout(700);
    гнездо.on('connect', () => конец(true));
    гнездо.on('timeout', () => конец(false));
    гнездо.on('error', () => конец(false));
  });
}

function поднятьКомнаты() {
  return new Promise(function (готово, беда) {
    /* «--без-памяти» обязателен: без него наши комнаты попадут в настоящую
       статистику владельца. */
    const дитя = spawn('node', [path.join(КОРЕНЬ, 'server', 'сервер.js'), String(ПОРТ_КОМНАТ), '--без-памяти']);
    let вывод = '';
    const срок = setTimeout(() => { дитя.kill(); беда(new Error('сервер комнат не поднялся за 15 секунд')); }, 15000);
    дитя.stdout.on('data', (кусок) => {
      вывод += кусок;
      if (/работает на порту/.test(вывод)) { clearTimeout(срок); готово(дитя); }
    });
  });
}

