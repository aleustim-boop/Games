const спать = (мс) => new Promise((ф) => setTimeout(ф, мс));

/** Нажать, если кнопка есть и видна. Нужно там, где путь стал короче:
    «Играть с ботом» теперь ведёт сразу за стол, и отдельной кнопки
    «Играть» на дороге может не быть вовсе. */
/**
 * Дождаться, пока кнопка станет видна, и нажать. Пауз по часам тут мало:
 * экран меняется не мгновенно, и на занятой машине «поспать 300 мс»
 * иногда кончается раньше, чем появляется кнопка. Тогда playwright ждёт
 * невидимый узел тридцать секунд и роняет весь стенд — вместе со всеми
 * замерами, которые шли следом.
 */
async function нажатьКогдаВидна(страница, примета, потолокМс) {
  const начало = Date.now();
  while (Date.now() - начало < (потолокМс || 8000)) {
    const видна = await страница.evaluate((п) => {
      const к = document.querySelector(п);
      return Boolean(к && к.offsetParent !== null);
    }, примета);
    if (видна) { await страница.click(примета, { timeout: 4000 }); return true; }
    await спать(50);
  }
  console.log('    (кнопку ' + примета + ' так и не дождались за ' + (потолокМс || 8000) + ' мс)');
  return false;
}

/**
 * Быстрый сценарий для --сломать-шапку: только вкладка «Рейтинг» лобби
 * дурака на 390×844 (без второй игры и без двух других ширин экрана —
 * им шапка рейтинга не касается). «адрес» — свой временный сервер,
 * раздающий файлы проекта как есть; «испорченныйCssФайл» — путь к
 * порченой КОПИИ style.css во временной папке, её сюда подсовывает
 * playwright (route), сервер про неё не знает вовсе.
 */
async function быстраяПроверкаШапкиРейтинга(браузер, адрес, испорченныйCssФайл) {
  const размер = РАЗМЕРЫ[0];
  console.log('\n--- --сломать-шапку: вкладка «Рейтинг» дурака, ' + размер.имя + ' ---');
  const окно = await браузер.newContext({ viewport: { width: размер.ш, height: размер.в }, hasTouch: true });
  const страница = await окно.newPage();
  // Подмена ТОЛЬКО на уровне playwright: настоящий style.css на диске
  // не трогаем, сервер отдаёт его как есть — а тут прямо в браузер
  // подсовываем испорченную копию из tmpdir. Regex, не glob: страница
  // просит «/style.css?v=NN», glob такое не ловит.
  await страница.route(/\/style\.css(?:\?|$)/, (route) => route.fulfill({
    path: испорченныйCssФайл, contentType: 'text/css; charset=utf-8'
  }));
  await подготовитьПодделку(страница, {
    версия: '8.0', полныйЭкран: 'дают',
    отступы: {
      системные: { top: СВЕРХУ_СИСТЕМА, bottom: ЗАПРЕТ_СНИЗУ, left: 0, right: 0 },
      содержимого: { top: СВЕРХУ_ТЕЛЕГРАМ, bottom: 0, left: 0, right: 0 }
    }
  });
  await страница.goto(адрес);
  await спать(600);
  await нажатьКогдаВидна(страница, '#кнопка-игра-дурак'); await спать(300);
  await нажатьКогдаВидна(страница, '#лобби-вкладка-рейтинг'); await спать(600);
  await дождатьсяПокоя(страница);
  // Структура шапки («Назад» — первый узел) от порчи CSS не зависит и
  // должна остаться true — это подтверждает, что покраснеет именно
  // проверка положения, а не случайный сторонний эффект.
  const шапкаЗамер = await страница.evaluate(() => {
    const шапка = document.querySelector('.рейтинг-шапка');
    const к = document.getElementById('кнопка-рейтинг-игроков-назад');
    return {
      структура: Boolean(шапка && к && шапка.contains(к) && шапка.firstElementChild === к && к.classList.contains('рейтинг-шапка__назад')),
      верхШапки: шапка ? Math.round(шапка.getBoundingClientRect().top) : null
    };
  });
  console.log('    верх шапки рейтинга на испорченном style.css: ' + шапкаЗамер.верхШапки + 'px (ждём < ' + ЗАПРЕТ_СВЕРХУ + ', структура шапки: ' + шапкаЗамер.структура + ')');
  проверить(шапкаЗамер.структура, '--сломать-шапку: структура шапки («Назад» первым узлом) порчей CSS не задета');
  // Ровно та же проверка, что мерит любой другой экран стенда (никакой
  // второй копии числа/формулы) — «померить» сама печатает верх/низ/
  // ширину и сама роняет «верх не под часами Telegram», если он упал.
  await померить(страница, 'рейтинг игроков (--сломать-шапку, style.css испорчен)', размер);
  await окно.close();
}

/**
 * Шаг «назад», как его делает человек. С 11 сентября внутри Telegram
 * оформление прячет кнопки «‹» на «Как играть», «Рекордах» и «Оформлении»:
 * там уходят стрелкой «Назад» самого Telegram. Стенд ждал спрятанную
 * кнопку, не дожидался — и оставался на правилах: все следующие шаги
 * мерили не тот экран. Теперь: видна кнопка — жмём её, нет — стрелку.
 */
async function назадКакЧеловек(страница, примета) {
  const начало = Date.now();
  while (Date.now() - начало < 1500) {
    const видна = await страница.evaluate((п) => {
      const к = document.querySelector(п);
      return Boolean(к && к.offsetParent !== null);
    }, примета);
    if (видна) { await страница.click(примета, { timeout: 4000 }); return 'кнопкой'; }
    await спать(50);
  }
  const стрелка = await страница.evaluate(() => {
    const в = window.Telegram && window.Telegram.WebApp;
    if (!в || !в.BackButton || !в.BackButton.isVisible || !window.ПоддельныйТелеграм) return false;
    window.ПоддельныйТелеграм.нажатьНазад();
    return true;
  });
  if (!стрелка) console.log('    (ни кнопки ' + примета + ', ни стрелки Telegram — назад уйти нечем)');
  return стрелка ? 'стрелкой Telegram' : 'никак';
}

async function нажатьЕслиЕсть(страница, примета) {
  try {
    const видна = await страница.evaluate((п) => {
      const к = document.querySelector(п);
      return !!(к && к.offsetParent !== null);
    }, примета);
    if (!видна) return false;
    await страница.click(примета, { timeout: 4000 });
    return true;
  } catch (сбой) { return false; }
}

