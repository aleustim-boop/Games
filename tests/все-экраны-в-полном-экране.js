const ПРАВИЛО_ОТСТУПА_СВЕРХУ = /--отступ-сверху:\s*max\([^;]+\);/;
function путьКИспорченнойКопииStyleCss() {
  const исходныйПуть = path.join(КОРЕНЬ, 'style.css');
  const исходник = fs.readFileSync(исходныйПуть, 'utf8');
  if (!ПРАВИЛО_ОТСТУПА_СВЕРХУ.test(исходник)) {
    console.log('ОШИБКА: в style.css не нашлась строка «--отступ-сверху: max(...);» —');
    console.log('приём порчи устарел (правило переименовали или переписали иначе), этот тест надо обновить.');
    process.exit(1);
  }
  const испорченный = исходник.replace(ПРАВИЛО_ОТСТУПА_СВЕРХУ, '--отступ-сверху: 0px; /* порчено --сломать-шапку, копия */');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'сломать-шапку-'));
  const файл = path.join(папка, 'style.css');
  fs.writeFileSync(файл, испорченный, 'utf8');
  return файл;
}
const ТИПЫ_ФАЙЛОВ_ПОДМЕНЫ = {
  '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8', '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg', '.webp': 'image/webp', '.woff2': 'font/woff2'
};
function запрещённыйАдресДляПодмены(адрес) {
  const низ = адрес.toLowerCase();
  if (низ.indexOf('.env') !== -1) return true;
  const части = низ.split(/[\\/]/).filter(Boolean);
  if (части.length && части[0] === 'bot') return true;
  return части.some((часть) => часть.charAt(0) === '.');
}
/** Обычная раздача файлов проекта как есть — без спецкейсов подмены:
    испорченный style.css подсовывается не сервером, а playwright'ом
    (страница.route), сервер тут только страницы отдаёт. */
function поднятьПростойСервисСтраниц() {
  return new Promise((готово) => {
    const сервер = http.createServer((запрос, ответ) => {
      let адрес;
      try { адрес = decodeURIComponent(запрос.url.split('?')[0]); }
      catch (о) { ответ.writeHead(400); ответ.end('непонятный адрес'); return; }
      if (адрес === '/') адрес = '/index.html';
      if (запрещённыйАдресДляПодмены(адрес)) { ответ.writeHead(403); ответ.end('доступ закрыт'); return; }
      const файл = path.join(КОРЕНЬ, адрес.replace(/^\/+/, ''));
      if (файл !== КОРЕНЬ && !файл.startsWith(КОРЕНЬ + path.sep)) { ответ.writeHead(403); ответ.end('доступ закрыт'); return; }
      fs.readFile(файл, (ошибка, данные) => {
        if (ошибка) { ответ.writeHead(404); ответ.end('не найдено: ' + адрес); return; }
        ответ.writeHead(200, {
          'Content-Type': ТИПЫ_ФАЙЛОВ_ПОДМЕНЫ[path.extname(файл).toLowerCase()] || 'application/octet-stream',
          'Cache-Control': 'no-store'
        });
        ответ.end(данные);
      });
    });
    сервер.listen(0, '127.0.0.1', () => готово(сервер));
  });
}

