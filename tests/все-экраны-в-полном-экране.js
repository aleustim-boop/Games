/**
 * Дождаться, пока экран успокоится. Меряем не «через столько-то мс»,
 * а когда верх содержимого перестал меняться два замера подряд.
 * Иначе мерка попадает в середину раздачи: карты летят сверху, и верх
 * содержимого на миг оказывается выше, чем на самом деле (видели 55
 * при настоящих 67).
 */
async function дождатьсяПокоя(страница, сколькоЖдатьМс) {
  const срок = Date.now() + (сколькоЖдатьМс || 4000);
  let прошлый = null;
  while (Date.now() < срок) {
    const сейчас = await страница.evaluate(() => {
      const все = document.querySelectorAll('.экран.экран--виден');
      const э = все[все.length - 1];
      if (!э) return 'нет экрана';
      let верх = 99999;
      э.querySelectorAll('*').forEach((у) => {
        if (у.children.length) return;
        const к = у.getBoundingClientRect();
        if (к.width < 2 || к.height < 2) return;
        const с = getComputedStyle(у);
        if (с.visibility === 'hidden' || с.display === 'none' || Number(с.opacity) === 0) return;
        верх = Math.min(верх, Math.round(к.top));
      });
      return э.id + ':' + верх;
    });
    if (сейчас === прошлый) return сейчас;
    прошлый = сейчас;
    await new Promise((ф) => setTimeout(ф, 300));
  }
  return прошлый;
}

