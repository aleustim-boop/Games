/*
 * До 11 сентября здесь был контрольный замер экрана «Игра с ботом»:
 * низ его «Назад» (оформитель считал «примерно 798»), просвет между
 * «Играть» и пояснением, высота кнопок «Звук» и «Рекорды». Этого экрана
 * больше нет — вместо него лобби и три шага, и прежние числа потеряли
 * смысл вместе с ним. Взамен меряем то, что на шагах важно пальцу:
 * главная кнопка шага («Далее» / «Начать игру») не ниже 44 точек и
 * достижима — либо над полосой жеста, либо прокруткой.
 */
async function контрольныйЗамерШага(страница, размер, имя) {
  const м = await страница.evaluate(() => {
    const экран = document.querySelector('.экран.экран--виден');
    const кнопка = экран && экран.querySelector('[data-путь="далее"]');
    if (!кнопка || !кнопка.offsetParent) return { экран: экран ? экран.id : '', кнопки: null };
    /* Прокрутка может быть у самого экрана или у его внутренней части —
       берём наибольший запас от кнопки вверх до экрана. */
    let прокрутка = 0;
    for (let у = кнопка; у && у !== экран.parentElement; у = у.parentElement) {
      прокрутка = Math.max(прокрутка, у.scrollHeight - у.clientHeight);
    }
    const к = кнопка.getBoundingClientRect();
    return { экран: экран.id, кнопки: { верх: Math.round(к.top), низ: Math.round(к.bottom), высота: Math.round(к.height),
      надпись: кнопка.textContent.trim() }, прокрутка: Math.max(0, прокрутка) };
  });
  if (!м.кнопки) { проверить(false, имя + ': главной кнопки шага не нашлось на экране ' + м.экран); return; }
  const граница = размер.в - ЗАПРЕТ_СНИЗУ;
  console.log('    контрольный замер «' + имя + '»: «' + м.кнопки.надпись + '» ' + м.кнопки.верх + '..' + м.кнопки.низ +
    ' при границе полосы жеста ' + граница + ', прокрутка ' + м.прокрутка + 'px');
  проверить(м.кнопки.высота >= 44, имя + ': «' + м.кнопки.надпись + '» не ниже 44 точек под палец: ' + м.кнопки.высота);
  проверить(м.кнопки.низ <= граница || м.прокрутка > 0,
    имя + ': «' + м.кнопки.надпись + '» над полосой жеста или доезжает прокруткой (низ ' + м.кнопки.низ + ', граница ' + граница + ')');
}

