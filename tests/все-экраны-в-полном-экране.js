/** Один тап по доске: поднять шашку или пойти на подсвеченную клетку. */
function тапнуть(страница) {
  return страница.evaluate(() => {
    const случайный = (список) => список[Math.floor(Math.random() * список.length)];
    const куда = document.querySelectorAll('.поле--можно, .поле--можно-бой');
    if (куда.length > 0) { случайный(Array.from(куда)).click(); return 'ход'; }
    const свои = document.querySelectorAll('.фишка--может-ходить');
    if (свои.length > 0) { случайный(Array.from(свои)).parentElement.click(); return 'поднял'; }
    return 'нечего';
  });
}

async function обойтиШашки(браузер, размер) {
  console.log('\n--- Шашки, ' + размер.имя + ' ---');
  const окно = await браузер.newContext({ viewport: { width: размер.ш, height: размер.в }, hasTouch: true });
  const страница = await окно.newPage();
  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
    красные.push('консоль: ' + м.text());
  });
  await подготовитьПодделку(страница, {
    версия: '8.0', полныйЭкран: 'дают',
    отступы: {
      системные: { top: СВЕРХУ_СИСТЕМА, bottom: ЗАПРЕТ_СНИЗУ, left: 0, right: 0 },
      содержимого: { top: СВЕРХУ_ТЕЛЕГРАМ, bottom: 0, left: 0, right: 0 }
    }
  });
  await страница.goto('http://127.0.0.1:' + ПОРТ_СТРАНИЦ + '/шашки.html?сервер=http://127.0.0.1:' + ПОРТ_КОМНАТ);
  await спать(600);

  await дождатьсяПокоя(страница); await померить(страница, 'выбор соперника', размер);

  /* Путь с ботом: нажимаем и сразу попадаем в партию, потом возвращаемся
     на лобби, чтобы проверить другие пути. */
  await страница.click('#лобби-боты'); await спать(400);
  await дождатьсяПокоя(страница); await померить(страница, 'доска', размер);
  const вМенюВидна = await нажатьЕслиЕсть(страница, '#кнопка-в-меню');
  if (!вМенюВидна) {
    await страница.evaluate(() => window.ПоддельныйТелеграм && window.ПоддельныйТелеграм.нажатьНазад());
  }
  await спать(300);

  /* Игра с другом у шашек появилась только что и ещё достраивается,
     поэтому идём мягко: нет кнопки или экран не открылся — говорим об этом
     и идём дальше, а не роняем весь обход. */
  if (await попробоватьНажать(страница, '#лобби-друг')) {
    await дождатьсяПокоя(страница); await померить(страница, 'игра с другом', размер);
    if (await попробоватьНажать(страница, '#кнопка-создать-игру', 1500)) {
      await дождатьсяПокоя(страница); await померить(страница, 'комната с кодом', размер);
      await попробоватьНажать(страница, '#кнопка-комната-отмена', 800);
    }
    if (await попробоватьНажать(страница, '#кнопка-войти-по-коду')) {
      await дождатьсяПокоя(страница); await померить(страница, 'вход по коду', размер);
      await попробоватьНажать(страница, '#кнопка-вход-назад');
    }
    await попробоватьНажать(страница, '#кнопка-друг-назад');
  }

  /* Партию берём «вдвоём на одном телефоне»: она идёт быстро — робот не думает */
  await страница.click('#лобби-вдвоём'); await спать(600);
  await дождатьсяПокоя(страница); await померить(страница, 'доска', размер);

  if (await попробоватьНажать(страница, '#кнопка-как-играть')) {
    await дождатьсяПокоя(страница); await померить(страница, 'правила', размер);
    await попробоватьНажать(страница, '#кнопка-правила-назад');
  }

  if (await попробоватьНажать(страница, '#кнопка-рекорды')) {
    await дождатьсяПокоя(страница); await померить(страница, 'рекорды', размер);
    await попробоватьНажать(страница, '#кнопка-рекорды-назад');
  }

  let тапов = 0;
  for (let i = 0; i < 900; i++) {
    const кончено = await страница.evaluate(() =>
      document.getElementById('экран-итога').classList.contains('экран--виден'));
    if (кончено) break;
    const что = await тапнуть(страница);
    тапов++;
    await спать(что === 'нечего' ? 120 : 25);
  }
  const дошло = await страница.evaluate(() =>
    document.getElementById('экран-итога').classList.contains('экран--виден'));
  проверить(дошло, 'партия в шашках доиграна до плашки итога, тапов ' + тапов);
  if (дошло) await дождатьсяПокоя(страница); await померить(страница, 'плашка итога', размер);

  проверить(красные.length === 0, 'за весь обход ни одной красной строки' +
    (красные.length ? ': ' + красные.slice(0, 3).join(' | ') : ''));
  await окно.close();
}

