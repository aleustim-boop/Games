/**
 * Оформитель ужал этот экран на 65 точек понемногу отовсюду, и запас
 * у него всего 12 точек — считал он по правилам в файле, а не с экрана.
 * Поэтому меряем прицельно и числами: где кончается кнопка «Назад»,
 * не ниже ли 44 точек кнопки (палец) и не слиплась ли «Играть»
 * с пояснением над ней.
 *
 * На 390×844 экран обязан помещаться целиком. На узких телефонах
 * (360×640, 320×568) он не помещался и раньше — там смотрим только
 * на кнопки и просветы, а прокрутку считаем нормой.
 */
async function контрольныйЗамерНастройкиСтола(страница, размер) {
  /* Настройки стола теперь СВЁРНУТЫ: на экране остаётся то, чем выбирают
     (соперник и «Играть»), а слова про переводного и парами лежат за
     кнопкой «Ещё настройки». Пояснение под ними — тоже. Раскрываем блок,
     иначе меряем свёрнутый экран и честно не находим пояснения. */
  await нажатьКогдаВидна(страница, '#кнопка-ещё-настройки', 3000);
  await спать(250);
  const м = await страница.evaluate(() => {
    const взять = (id) => {
      const у = document.getElementById(id);
      if (!у || !у.offsetParent) return null;
      const к = у.getBoundingClientRect();
      return { верх: Math.round(к.top), низ: Math.round(к.bottom), высота: Math.round(к.height) };
    };
    const экран = document.getElementById('экран-бота');
    return {
      назад: взять('кнопка-бот-назад'),
      играть: взять('кнопка-играть'),
      пояснение: взять('меню-пояснение-стола'),
      звук: взять('кнопка-звук'),
      рекорды: взять('кнопка-рекорды'),
      прокрутка: Math.max(0, экран.scrollHeight - экран.clientHeight)
    };
  });

  const граница = размер.в - ЗАПРЕТ_СНИЗУ;
  console.log('    контрольный замер «Игра с ботом»: низ «Назад» ' + (м.назад ? м.назад.низ : '?') +
    ' при границе полосы жеста ' + граница + ', прокрутка ' + м.прокрутка + 'px');

  if (размер.ш === 390) {
    /* Главное — кнопка не должна уходить под полосу жеста. Оформитель считал
       по правилам в файле и ждал «примерно 798»; если на экране вышло выше,
       это только лучше — про такое пишем замечанием, а не провалом. Провал
       один: если кнопка ушла ниже границы. */
    проверить(м.назад && м.назад.низ <= граница,
      'кнопка «Назад» помещается над полосой жеста: низ ' + (м.назад ? м.назад.низ : '?') + ' ≤ ' + граница);
    if (м.назад && Math.abs(м.назад.низ - 798) > 12) {
      замечаний++;
      console.log('    (замечание: оформитель считал «примерно 798», на экране вышло ' + м.назад.низ +
        ' — расхождение ' + (798 - м.назад.низ) + ' точек' +
        (м.назад.низ < 798 ? ', запас больше обещанного' : ', запас меньше обещанного') + ')');
    }
    проверить(м.прокрутка === 0, 'на 390×844 экран помещается целиком, прокрутки нет (прокрутка ' + м.прокрутка + 'px)');
  } else {
    console.log('    (на ' + размер.имя + ' экран не помещался и раньше — прокрутка ' + м.прокрутка + 'px здесь норма)');
  }

  /* Не слиплась ли «Играть» с пояснением над ней. */
  if (м.играть && м.пояснение) {
    const просвет = м.играть.верх - м.пояснение.низ;
    console.log('    просвет между пояснением и кнопкой «Играть»: ' + просвет + 'px');
    проверить(просвет >= 6, 'кнопка «Играть» не слиплась с пояснением (просвет ' + просвет + ' ≥ 6)');
  } else {
    проверить(false, 'не нашёл кнопку «Играть» или пояснение под настройками стола');
  }

  /* Кнопки под палец: ниже 44 точек опускать нельзя. */
  for (const [имя, что] of [['Играть', м.играть], ['Назад', м.назад], ['Звук', м.звук], ['Рекорды', м.рекорды]]) {
    if (!что) continue;
    проверить(что.высота >= 44, 'кнопка «' + имя + '» не ниже 44 точек под палец: ' + что.высота);
  }
}

