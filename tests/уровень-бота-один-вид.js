/* =====================================================================
   ЕДИНЫЙ ВИД ВЫБОРА УРОВНЯ БОТА (шашки, нарды, шахматы).

   Правило владельца — «все игры выглядят одинаково», эталон — дурак.
   Дурак и шахматы рисуют выбор сложности бота общим компонентом
   «.переключатель» / «.переключатель__вариант» (style.css ~11175) и
   отмечают выбранный вариант классом «переключатель__вариант--выбран»
   (дурак: js/дурак-путь.js, шахматы: js/шахматы-лобби.js). В шашках и
   нардах тем же классом «переключатель__вариант» теперь размечены и
   кнопки уровня бота (шашки.html, нарды.html), но отмечает выбранную
   кнопку не эта разметка, а js/шашки-экран.js и js/нарды-экран.js —
   эти два файла вне задания, их не трогаем, они по-прежнему ставят
   класс «кнопка--активная». Чтобы вид совпадал один-в-один, style.css
   красит ОБА имени модификатора одним правилом (~11216) — эта проверка
   ловит именно то, что реально видит игрок: вычисленный CSS
   (getComputedStyle) выбранной и невыбранной кнопки должен быть
   идентичен во всех трёх играх, а не совпадение имён классов.

   СВОЙ СТАТИЧЕСКИЙ СЕРВЕР — ПРЯМО В ЭТОМ ФАЙЛЕ, по образцу
   tests/снимок-рейтинг-золото.js: только так можно на лету подменить
   отдачу style.css испорченной копией для ломающего запуска, не трогая
   настоящий файл ни на секунду.

   Запуск:
       node tests/уровень-бота-один-вид.js              — чистый прогон,
           заодно кладёт три снимка лобби на шаге выбора уровня бота в
           tests/снимки/ (уровень-бота-<игра>-390.png).
       node tests/уровень-бота-один-вид.js --сломать    — ломающий прогон:
           портит КОПИЮ style.css во временной папке (os.tmpdir(), не
           файл проекта) — возвращает объединённое правило «~11216» к
           старому однострочному виду (только «переключатель__вариант--
           выбран», без «кнопка--активная»). После такой порчи выбранный
           уровень в шашках и в нардах перестаёт получать салатовый фон
           (его по-прежнему красит только «кнопка--активная»), а в
           шахматах — не меняется (там всегда стоит «переключатель__
           вариант--выбран»). Сравнение «выбранная кнопка одинакова во
           всех трёх играх» обязано провалиться — это и есть красный
           результат, который требуется от ломающего запуска.
   ===================================================================== */

