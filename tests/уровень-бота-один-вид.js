const http = require('http');
const { chromium, подготовитьПодделку } = require('./браузер-робот.js');

const КОРЕНЬ = path.join(__dirname, '..');
const ПУТЬ_СТИЛЯ = path.join(КОРЕНЬ, 'style.css');
const ПАПКА_СНИМКОВ = path.join(__dirname, 'снимки');
const ШИРИНА = 390;
const ВЫСОТА = 844;
const АДРЕС_ХОЗЯИНА = '127.0.0.1';
const ЗАПРЕЩЁННЫЕ_ПОРТЫ = [8790, 8791];

const сломать = process.argv.indexOf('--сломать') !== -1;

let проверок = 0;
const провалы = [];

function проверить(что, условие, подробности) {
  проверок++;
  if (условие) { console.log('  ок    — ' + что); return; }
  провалы.push(что + (подробности ? ' (' + подробности + ')' : ''));
  console.log('  ПРОВАЛ — ' + что + (подробности ? ': ' + подробности : ''));
}

/* ---------------------------------------------------------------------
   Мелкие утилиты — порт, статическая раздача с подменой style.css.
   Дословно тот же приём, что в tests/снимок-рейтинг-золото.js.
   --------------------------------------------------------------------- */

function свободныйПорт() {
  return new Promise((готово, брак) => {
    const проба = http.createServer();
    проба.on('error', брак);
    проба.listen(0, АДРЕС_ХОЗЯИНА, () => {
      const порт = проба.address().port;
      проба.close(() => готово(порт));
    });
  });
}

async function выбратьСвободныйПорт() {
  for (let попытка = 0; попытка < 6; попытка++) {
    const порт = await свободныйПорт();
    if (ЗАПРЕЩЁННЫЕ_ПОРТЫ.indexOf(порт) === -1) return порт;
  }
  throw new Error('не удалось получить свободный порт, отличный от боевых 8790/8791');
}

const ТИПЫ_ФАЙЛОВ = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.woff2': 'font/woff2'
};

function запрещённыйАдрес(адрес) {
  const низ = адрес.toLowerCase();
  if (низ.indexOf('.env') !== -1) return true;
  const части = низ.split(/[\\/]/).filter(Boolean);
  if (части.length && части[0] === 'bot') return true;
  return части.some((часть) => часть.charAt(0) === '.');
}

function поднятьСервер(порт, подменаStyleCss) {
  return new Promise((готово) => {
    const сервер = http.createServer((запрос, ответ) => {
      let адрес;
      try {
        адрес = decodeURIComponent(запрос.url.split('?')[0]);
      } catch (ошибка) {
        ответ.writeHead(400); ответ.end('непонятный адрес'); return;
      }
      if (адрес === '/') адрес = '/index.html';
      if (запрещённыйАдрес(адрес)) { ответ.writeHead(403); ответ.end('доступ закрыт'); return; }

      if (подменаStyleCss !== null && адрес === '/style.css') {
        ответ.writeHead(200, { 'Content-Type': 'text/css; charset=utf-8', 'Cache-Control': 'no-store' });
        ответ.end(подменаStyleCss);
        return;
      }

      const относительный = адрес.replace(/^\/+/, '');
      const файл = path.join(КОРЕНЬ, относительный);
      if (файл !== КОРЕНЬ && !файл.startsWith(КОРЕНЬ + path.sep)) {
        ответ.writeHead(403); ответ.end('доступ закрыт: файл вне папки проекта'); return;
      }

      fs.readFile(файл, (ошибка, данные) => {
        if (ошибка) { ответ.writeHead(404); ответ.end('не найдено: ' + адрес); return; }
        ответ.writeHead(200, {
          'Content-Type': ТИПЫ_ФАЙЛОВ[path.extname(файл).toLowerCase()] || 'application/octet-stream',
          'Cache-Control': 'no-store'
        });
        ответ.end(данные);
      });
    });
    сервер.listen(порт, АДРЕС_ХОЗЯИНА, () => готово(сервер));
  });
}

/* ---------------------------------------------------------------------
   Готовим испорченную КОПИЮ style.css для «--сломать» — только в
   os.tmpdir(), настоящий файл проекта не трогается ни на секунду.
   --------------------------------------------------------------------- */

function испортитьКопиюСтиля(оригинал) {
  const ДОСЛОВНЫЙ_БЛОК = '.переключатель__вариант.переключатель__вариант--выбран,\n' +
    '.переключатель__вариант.кнопка--активная {';
  const ДОСЛОВНЫЙ_БЛОК_DISABLED = '.переключатель__вариант.переключатель__вариант--выбран:disabled,\n' +
    '.переключатель__вариант.кнопка--активная:disabled {';

  if (оригинал.indexOf(ДОСЛОВНЫЙ_БЛОК) === -1 || оригинал.indexOf(ДОСЛОВНЫЙ_БЛОК_DISABLED) === -1) {
    throw new Error('в style.css не нашёлся объединённый селектор «--выбран, .кнопка--активная» — приём поменялся, обновите эту проверку');
  }

  const испорченный = оригинал
    .replace(ДОСЛОВНЫЙ_БЛОК, '.переключатель__вариант.переключатель__вариант--выбран {')
    .replace(ДОСЛОВНЫЙ_БЛОК_DISABLED, '.переключатель__вариант.переключатель__вариант--выбран:disabled {');

  const путьКопии = path.join(os.tmpdir(), 'games-уровень-бота-испорченный-style-' + Date.now() + '.css');
  fs.writeFileSync(путьКопии, испорченный, 'utf8');
  const текстСДиска = fs.readFileSync(путьКопии, 'utf8');
  return { путьКопии, текстСДиска, отличается: текстСДиска !== оригинал };
}

