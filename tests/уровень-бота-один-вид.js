/** Открыть игру тем же путём, что и игрок: лобби → «Играть с ботом» →
 *  второй шаг с уровнем бота. Возвращает число найденных видимых кнопок
 *  в ряду (0 — честный провал, а не тихо пропущенная проверка) и
 *  вычисленный вид выбранной и соседней невыбранной кнопки. */
async function замерить(страница, порт, игра, снятьСнимок) {
  await страница.goto('http://' + АДРЕС_ХОЗЯИНА + ':' + порт + '/' + игра.файл);
  await страница.waitForSelector('#экран-лобби.экран--виден', { timeout: 10000 });
  await страница.click('#лобби-боты');
  await страница.waitForSelector(игра.контейнерВторогоШага + '.экран--виден', { timeout: 10000 });
  await страница.waitForTimeout(300);

  if (снятьСнимок) {
    await страница.screenshot({ path: снятьСнимок });
  }

  return страница.evaluate(({ рядСелектор, идВыбранного, идНевыбранного }) => {
    function снятьВид(узел) {
      const в = getComputedStyle(узел);
      return {
        ид: узел.id,
        текст: узел.textContent.trim(),
        выбран: узел.classList.contains('переключатель__вариант--выбран') || узел.classList.contains('кнопка--активная'),
        фон: в.backgroundColor,
        цвет: в.color,
        рамкаШирина: в.borderTopWidth,
        рамкаСтиль: в.borderTopStyle,
        рамкаЦвет: в.borderTopColor
      };
    }

    const ряд = document.querySelector(рядСелектор);
    const кнопки = ряд
      ? Array.from(ряд.querySelectorAll('button')).filter((узел) => узел.offsetParent !== null)
      : [];

    const выбранныйУзел = document.getElementById(идВыбранного);
    const невыбранныйУзел = document.getElementById(идНевыбранного);

    return {
      кнопокНайдено: кнопки.length,
      выбранный: выбранныйУзел ? снятьВид(выбранныйУзел) : null,
      невыбранный: невыбранныйУзел ? снятьВид(невыбранныйУзел) : null
    };
  }, { рядСелектор: игра.рядУровня, идВыбранного: игра.выбранныйИд, идНевыбранного: игра.невыбранныйИд });
}

/** Одинаковый ли вычисленный вид (фон, цвет, рамка) у двух кнопок. */
function видОдинаков(а, б) {
  if (!а || !б) return false;
  return а.фон === б.фон && а.цвет === б.цвет &&
    а.рамкаШирина === б.рамкаШирина && а.рамкаСтиль === б.рамкаСтиль && а.рамкаЦвет === б.рамкаЦвет;
}

function описатьВид(в) {
  if (!в) return 'узел не найден';
  return 'фон=' + в.фон + ' цвет=' + в.цвет + ' рамка=' + в.рамкаШирина + ' ' + в.рамкаСтиль + ' ' + в.рамкаЦвет;
}

/* ---------------------------------------------------------------------
   Основной прогон.
   --------------------------------------------------------------------- */

(async function () {
  console.log('=== Уровень бота: один вид во всех играх (шашки, нарды, шахматы) ===' +
    (сломать ? '  [режим «--сломать»]' : ''));

  if (!fs.existsSync(ПАПКА_СНИМКОВ)) fs.mkdirSync(ПАПКА_СНИМКОВ, { recursive: true });

  const текстСтиляОригинала = fs.readFileSync(ПУТЬ_СТИЛЯ, 'utf8');
  let подменаStyleCss = null;
  let путьИспорченнойКопии = null;

  if (сломать) {
    const порча = испортитьКопиюСтиля(текстСтиляОригинала);
    путьИспорченнойКопии = порча.путьКопии;
    подменаStyleCss = порча.текстСДиска;
    console.log('  копия испорченного style.css: ' + путьИспорченнойКопии +
      ' (настоящий style.css не тронут)');
    проверить('копия испорченного style.css действительно отличается от оригинала', порча.отличается);
  }

  const порт = await выбратьСвободныйПорт();
  const сервер = await поднятьСервер(порт, подменаStyleCss);

  const браузер = await chromium.launch();
  let сбой = null;

  try {
    const контекст = await браузер.newContext({ viewport: { width: ШИРИНА, height: ВЫСОТА }, hasTouch: true });
    const страница = await контекст.newPage();
    const красные = [];
    страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
    страница.on('console', (м) => {
      if (м.type() !== 'error') return;
      // В тестовой среде нет сети наружу — настоящий telegram-web-app.js
      // с telegram.org честно не грузится (net::ERR_FAILED). Это не
      // поломка проверяемого кода, а особенность стенда: тот же фильтр
      // стоит в tests/нарды-уровень-мастер.js.
      const откуда = (м.location && м.location() && м.location().url) || '';
      if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
      красные.push('консоль: ' + м.text());
    });

    await подготовитьПодделку(страница, { версия: '8.0' });

    const данные = {};
    for (const игра of ИГРЫ) {
      const снимок = (!сломать) ? path.join(ПАПКА_СНИМКОВ, 'уровень-бота-' + игра.имя + '-390.png') : null;
      const замер = await замерить(страница, порт, игра, снимок);
      данные[игра.имя] = замер;

      console.log('  ' + игра.имя + ': кнопок в ряду видно ' + замер.кнопокНайдено +
        '; выбранная «' + (замер.выбранный ? замер.выбранный.текст : '?') + '» — ' + описатьВид(замер.выбранный) +
        '; невыбранная «' + (замер.невыбранный ? замер.невыбранный.текст : '?') + '» — ' + описатьВид(замер.невыбранный));
      if (снимок) console.log('     снимок: ' + снимок);

      проверить(игра.имя + ': в ряду уровня бота нашлись видимые кнопки (не ноль)', замер.кнопокНайдено > 0);
      проверить(игра.имя + ': кнопка «' + игра.выбранныйИд + '» отмечена выбранной',
        замер.выбранный !== null && замер.выбранный.выбран === true);
      проверить(игра.имя + ': соседняя кнопка «' + игра.невыбранныйИд + '» не отмечена выбранной',
        замер.невыбранный !== null && замер.невыбранный.выбран === false);
    }

    const пары = [['шашки', 'нарды'], ['шашки', 'шахматы'], ['нарды', 'шахматы']];
    for (const [а, б] of пары) {
      проверить('выбранная кнопка уровня бота выглядит одинаково: ' + а + ' и ' + б,
        видОдинаков(данные[а].выбранный, данные[б].выбранный),
        описатьВид(данные[а].выбранный) + '  vs  ' + описатьВид(данные[б].выбранный));
      проверить('невыбранная кнопка уровня бота выглядит одинаково: ' + а + ' и ' + б,
        видОдинаков(данные[а].невыбранный, данные[б].невыбранный),
        описатьВид(данные[а].невыбранный) + '  vs  ' + описатьВид(данные[б].невыбранный));
    }

    проверить('в консоли браузера ни одной ошибки', красные.length === 0, красные.join(' | '));

    await контекст.close();
  } catch (беда) {
    сбой = беда;
  }

  await браузер.close();
  сервер.close();

  console.log('\n----------------------------------------');
  if (сбой) console.log('ОБОРВАЛОСЬ: ' + (сбой.stack || сбой));
  if (путьИспорченнойКопии) console.log('копия испорченного style.css оставлена здесь: ' + путьИспорченнойКопии);
  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалы.length);
  провалы.forEach((что) => console.log('  · ' + что));
  process.exit((провалы.length === 0 && !сбой) ? 0 : 1);
})();
