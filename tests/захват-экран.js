// Что экран берёт при загрузке: эти файлы должны быть подключены раньше него.
const ФАЙЛЫ_ДО_ЭКРАНА_В_РАЗМЕТКЕ = ['telegram', 'лист-ещё', 'захват-карты', 'захват-правила', 'захват-память', 'захват-звук'];

/** Номера подключений js/<имя>.js в порядке страницы (с учётом того, что имя — целиком, до «.js?»). */
function местаПодключения(имя) {
  const места = [];
  const образец = /<script[^>]*src="js\/([^"?]+)\.js(?:\?[^"]*)?"/g;
  let м, номер = 0;
  while ((м = образец.exec(исходникСтраницы))) { if (м[1] === имя) места.push(номер); номер++; }
  return места;
}

function проверитьПодключениеЭкрана() {
  const сам = местаПодключения('захват-экран');
  проверка('страница: захват-экран.js подключён ровно один раз', сам.length === 1, 'найдено ' + сам.length);
  for (const имя of ФАЙЛЫ_ДО_ЭКРАНА_В_РАЗМЕТКЕ) {
    const места = местаПодключения(имя);
    проверка('страница: ' + имя + '.js подключён (ноль — провал) и раньше захват-экран.js',
      места.length >= 1 && сам.length === 1 && Math.max(...места) < сам[0], 'места ' + места.join() + ', экран ' + сам.join());
  }
}

