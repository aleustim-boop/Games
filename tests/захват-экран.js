/**
 * Поддельный innerHTML теги выбрасывает, а полоса вкладок собирается именно им:
 * экрану отдаём полосу через посредника, который разбирает разметку в настоящие узлы.
 */
function разбиратьПолосу(документ) {
  const искать = документ.querySelector;
  документ.querySelector = function (селектор) {
    const узел = искать.call(документ, селектор);
    if (!узел || !узел.classList.contains('нижние-вкладки')) return узел;
    return new Proxy(узел, {
      get: (цель, имя) => { const з = цель[имя]; return typeof з === 'function' ? з.bind(цель) : з; },
      set: (цель, имя, значение) => {
        if (имя !== 'innerHTML') { цель[имя] = значение; return true; }
        цель.replaceChildren();
        разобратьВ(String(значение), цель, документ);
        return true;
      }
    });
  };
}

/**
 * Поднять страницу. опции: память — { ключ: значение } заранее (кладётся как JSON);
 * вибрация — есть ли у телефона вибрация (по умолчанию да).
 */
function мир(опции) {
  const о = опции || {};
  const документ = сделатьДокумент();
  собратьРазметку(исходникСтраницы, документ);
  оживитьОкна(документ);
  разбиратьПолосу(документ);
  const память = сделатьПамять(false);
  for (const ключ of Object.keys(о.память || {})) память.setItem(ключ, JSON.stringify(о.память[ключ]));
  const р = поднять('', { память, документ });
  const ж = { окно: р.окно, документ, память, старты: [], продолжения: [], сдачи: [], отклики: [], стрелки: [], настройки: [], вибрация: { включена: true, вызовы: [] },
    рейтинги: [], профили: [] };
  р.окно.ЭкранРейтинга = { открыть: игра => { ж.рейтинги.push(игра); } };
  р.окно.ЭкранПрофиля = { открыть: игра => { ж.профили.push(игра); } };
  р.окно.Телеграм = {
    показатьСтрелку: дело => { ж.стрелки.push(дело); return true; },
    кнопкаНастроек: дело => { ж.настройки.push(дело); return true; },
    отклик: вид => { ж.отклики.push(вид); },
    имяИгрока: () => 'Аня',
    вибрацияДоступна: () => о.вибрация !== false,
    вибрацияВключена: () => ж.вибрация.включена,
    включитьВибрацию: ч => { ж.вибрация.включена = ч; ж.вибрация.вызовы.push(ч); }
  };
  for (const часть of ЧАСТИ_ДО_ЭКРАНА) {
    vm.runInContext(fs.readFileSync(path.join(КОРЕНЬ, 'js', часть), 'utf8'), р.песочница, { filename: 'js/' + часть });
  }
  vm.runInContext(исходникЭкрана, р.песочница, { filename: ФАЙЛ_ЭКРАНА });
  // Заглушки В8а/В8б заменяем следилками: настоящая партия в этом этапе не запускается.
  const экран = р.окно.ЗахватЭкран;
  if (экран) {
    экран.начатьПартиюСБотами = (партия, выбор) => { ж.старты.push({ партия, выбор }); };
    экран.продолжитьПартию = сохранение => { ж.продолжения.push(сохранение); };
    экран.сдатьсяВПартии = () => { ж.сдачи.push(1); };
  }
  ж.узел = id => документ.getElementById(id);
  ж.видимыйЭкран = id => !!ж.узел(id) && ж.узел(id).classList.contains('экран--виден');
  ж.нажать = id => { const у = ж.узел(id); if (!у) throw new Error('Нет узла ' + id); у.click(); };
  ж.нажатьПилюлю = (идГруппы, значение) => {
    const кнопка = ж.узел(идГруппы).querySelectorAll('button').filter(к => к.getAttribute('data-значение') === String(значение))[0];
    if (!кнопка) throw new Error('Нет пилюли ' + значение + ' в ' + идГруппы);
    кнопка.click();
  };
  ж.отмеченная = идГруппы => ж.узел(идГруппы).querySelectorAll('button')
    .filter(к => к.getAttribute('aria-checked') === 'true').map(к => к.getAttribute('data-значение'));
  ж.открытьЛист = () => ж.документ.querySelectorAll('[data-меню]')[0].click();
  ж.строкаЛиста = id => ж.узел(id);
  ж.видна = у => !!у && !у.classList.contains('скрыт');
  ж.подписиВидимыхСтрок = () => ж.документ.querySelectorAll('.лист-ещё__строка').filter(ж.видна)
    .map(у => у.querySelector('.лист-ещё__подпись').textContent);
  ж.ЗахватКарты = р.спросить('window.ЗахватКарты');
  ж.ЗахватПравила = р.спросить('window.ЗахватПравила');
  ж.ЗахватЗвук = р.спросить('window.ЗахватЗвук');
  ж.положение = р.окно.location;
  return ж;
}

