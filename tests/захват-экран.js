/** Копия страницы, где строка подключения экрана стоит перед захват-память.js. Не нашлось — вернуть без изменений. */
function переставитьЭкранПередПамятью(страница) {
  const строкаЭкрана = /<script src="js\/захват-экран\.js[^"]*"><\/script>\s*/.exec(страница);
  const память = /<script src="js\/захват-память\.js/.exec(страница);
  if (!строкаЭкрана || !память) return страница;
  const без = страница.replace(строкаЭкрана[0], '');
  const где = без.indexOf('<script src="js/захват-память.js');
  return без.slice(0, где) + строкаЭкрана[0] + без.slice(где);
}

function сломатьИПроверить(папка) {
  fs.mkdirSync(папка, { recursive: true });
  let худшийКод = 0;
  ПОРЧИ.forEach((порча, номер) => {
    const исходник = порча.что === 'экран' ? исходникЭкрана : исходникСтраницы;
    const испорчено = порча.сделать ? порча.сделать(исходник) : исходник.replace(порча.было, порча.стало);
    if (испорчено === исходник) {
      console.log('Порча ' + (номер + 1) + ' («' + порча.имя + '»): в копии нет места для порчи — код 3');
      худшийКод = Math.max(худшийКод, 3);
      return;
    }
    const копия = path.join(папка, 'порча-' + (номер + 1) + (порча.что === 'экран' ? '.js' : '.html'));
    fs.writeFileSync(копия, испорчено, 'utf8');
    const ключ = порча.что === 'экран' ? '--файл' : '--страница';
    const запуск = spawnSync(process.execPath, [__filename, ключ, копия], { encoding: 'utf8' });
    const красных = (запуск.stdout.match(/^ПРОВАЛ: .*/gm) || []);
    console.log('Порча ' + (номер + 1) + ' («' + порча.имя + '»): код выхода ' + запуск.status + ', красных пунктов ' + красных.length);
    красных.forEach(с => console.log('   ' + с));
    if (запуск.status !== 1 || !красных.length) худшийКод = Math.max(худшийКод, 2);
  });
  console.log(худшийКод === 0 ? 'Все порчи проверка поймала.' : 'Ломающий запуск не удался, код ' + худшийКод);
  process.exit(худшийКод);
}

