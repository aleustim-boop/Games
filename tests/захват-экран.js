  проверка('страница: нашлись кнопки «‹» и «⋯» (ноль — провал)', назады.length >= 3 && меню.length >= 3, 'назад ' + назады.length + ', меню ' + меню.length);
  проверка('страница: все «‹» и «⋯» — общая кнопка верха',
    [...назады, ...меню].every(к => к.classList.contains('верх-игры__кнопка') && к.parentNode.classList.contains('верх-игры')));
  const карточка = д.getElementById('лобби-найти-игру');
  проверка('страница: карточка «Играть онлайн» на месте', !!карточка);
  проверка('страница: карточка «Играть онлайн» видна (без hidden и без скрыт)',
    !!карточка && !карточка.hasAttribute('hidden') && !карточка.classList.contains('скрыт'));
