function довод(имя) {
  const и = process.argv.indexOf(имя);
  return и !== -1 ? process.argv[и + 1] : null;
}

/* ---------- сборка листа в песочнице ---------- */

/** Разметка листа как у большинства игр: лист > фон + колонка > строки + «Закрыть». */
function построитьЛист(документ) {
  const кнопкаЕщё = документ.узел('button', { id: 'кнопка-игра-ещё' });
  документ.body.appendChild(кнопкаЕщё);
  const колонка = документ.узел('div', { класс: 'лист-ещё__лист' });
  [['кнопка-лист-игры-меню', 'В меню'], ['кнопка-лист-игры-правила', 'Как играть'],
   ['кнопка-лист-игры-звук', 'Звук'], ['кнопка-лист-игры-рекорды', 'Рекорды']].forEach(function (п) {
    колонка.appendChild(документ.узел('button', { id: п[0], класс: 'лист-ещё__строка' },
      документ.узел('span', { класс: 'лист-ещё__подпись', текст: п[1] })));
  });
  колонка.appendChild(документ.узел('button', { класс: 'лист-ещё__закрыть' }));
  const лист = документ.узел('div', { id: 'лист-игры', класс: 'лист-ещё скрыт' },
    документ.узел('div', { id: 'лист-игры-фон' }), колонка);
  документ.body.appendChild(лист);
  return { кнопкаЕщё: кнопкаЕщё, лист: лист, колонка: колонка };
}

/** Один сценарий: свежий документ, свежий модуль листа, подключённый с данными дверями.
    «сТелеграмом» — есть ли строка «Во весь экран» (она тоже встаёт в конец листа). */
function собрать(путьКЛисту, двериИгры, сТелеграмом) {
  const документ = сделатьДокумент();
  const модуль = { exports: {} };
  const песочница = { module: модуль, exports: модуль.exports, console: console, document: документ,
    setTimeout: setTimeout, clearTimeout: clearTimeout };
  const экран = { полный: false };   // рукой переключаем «экран сейчас полный»
  if (сТелеграмом) {
    песочница.window = { Телеграм: {
      воВесьЭкран: function () {}, можноПолныйЭкран: function () { return true; },
      вПолномЭкране: function () { return экран.полный; } } };
  }
  vm.createContext(песочница);
  vm.runInContext(fs.readFileSync(путьКЛисту, 'utf8'), песочница, { filename: путьКЛисту + ' (в памяти)' });
  const Лист = модуль.exports;
  const разметка = построитьЛист(документ);
  const двери = Object.assign({
    вМеню: { действие: function () {} }, какИграть: { действие: function () {} },
    звук: { действие: function () {}, состояние: function () { return 'вкл'; } },
    рекорды: { действие: function () {} }
  }, двериИгры);
  const управление = Лист.подключить({ двери: двери });
  return { Лист: Лист, документ: документ, разметка: разметка, двери: двери, управление: управление, экран: экран };
}

/** Какие строки видны сейчас: id (или подпись, если id нет) по порядку сверху вниз. */
function видимыеСтроки(сц) {
  return сц.разметка.колонка.children
    .filter(function (у) { return у.classList.contains('лист-ещё__строка') && !у.classList.contains('скрыт'); })
    .map(function (у) { return у.id || у.textContent; });
}

function нажатьСтрокуСдаться(сц) {
  const узел = сц.документ.getElementById('кнопка-лист-игры-сдаться');
  if (узел) узел.click();
  return узел;
}

/* ---------- проверки ---------- */

function прогнать(путьКЛисту) {
  const итоги = { всего: 0, провалов: 0 };
  function надо(условие, что) {
    итоги.всего++;
    if (!условие) { итоги.провалов++; console.log('  ПРОВАЛ: ' + что); }
  }

  // 1. Без двери — лист как был (эталонный набор), узла «Сдаться» вообще нет.
  const без = собрать(путьКЛисту, {}, false);
  без.управление.открыть();
  const былоВДереве = видимыеСтроки(без);
  надо(былоВДереве.length === 4, 'без двери: на столе ровно 4 прежние строки, а не ' + былоВДереве.length);
  надо(без.документ.getElementById('кнопка-лист-игры-сдаться') === null, 'без двери: узла «Сдаться» нет в документе');
  надо(без.Лист.строкиЛиста(без.двери).every(function (с) { return с.ключ !== 'сдаться'; }),
    'без двери: строкиЛиста не отдаёт «сдаться»');
  const былоПоКлючам = без.Лист.строкиЛиста(без.двери).map(function (с) { return с.id; });

  // 2. С дверью — строка есть, последняя, красная, зовёт дверь ровно раз.
  let вызовов = 0;
  const с = собрать(путьКЛисту, { сдаться: { действие: function () { вызовов++; } } }, false);
  с.управление.открыть();
  const узел = с.документ.getElementById('кнопка-лист-игры-сдаться');
  надо(узел !== null, 'с дверью: узел «Сдаться» найден');
  const видно = видимыеСтроки(с);
  надо(видно.length === былоВДереве.length + 1, 'с дверью: строк на одну больше (' + видно.length + ')');
  надо(видно[видно.length - 1] === 'кнопка-лист-игры-сдаться', 'с дверью: «Сдаться» в листе последняя');
  надо(JSON.stringify(видно.slice(0, -1)) === JSON.stringify(былоВДереве),
    'с дверью: остальные строки те же и в том же порядке, что без двери');
  надо(Boolean(узел) && узел.classList.contains('лист-ещё__строка--опасно'), 'с дверью: у строки красный класс');
  надо(Boolean(узел) && узел.classList.contains('лист-ещё__строка'), 'с дверью: у строки общий класс строки листа');
  надо(Boolean(узел) && узел.textContent === 'Сдаться', 'с дверью: подпись «Сдаться»');
  надо(Boolean(узел) && с.разметка.колонка.children.indexOf(узел) === с.разметка.колонка.children.length - 2,
    'с дверью: в колонке «Сдаться» сразу перед «Закрыть»');
  const чистые = с.Лист.строкиЛиста(с.двери);
  надо(чистые.length > 0 && чистые[чистые.length - 1].ключ === 'сдаться', 'с дверью: строкиЛиста отдаёт «сдаться» последней');
  надо(JSON.stringify(чистые.slice(0, -1).map(function (р) { return р.id; })) === JSON.stringify(былоПоКлючам),
    'с дверью: строкиЛиста без последней совпадает с набором без двери');
  нажатьСтрокуСдаться(с);
  надо(вызовов === 1, 'нажатие зовёт дверь ровно раз (позвала ' + вызовов + ')');
  надо(с.управление.открыт() === false, 'после нажатия лист закрыт (подтверждение — дело экрана игры)');

  // 3. Дверь убрана (null) — строка пропала, набор снова прежний, нажать нельзя.
  с.двери.сдаться = null;
  с.управление.открыть();
  надо(JSON.stringify(видимыеСтроки(с)) === JSON.stringify(былоВДереве), 'дверь убрана: набор строк снова прежний');
  надо(с.документ.getElementById('кнопка-лист-игры-сдаться').classList.contains('скрыт'), 'дверь убрана: узел спрятан');
  нажатьСтрокуСдаться(с);
  надо(вызовов === 1, 'дверь убрана: нажатие скрытой строки дверь не зовёт');
  надо(с.Лист.строкиЛиста(с.двери).every(function (р) { return р.ключ !== 'сдаться'; }), 'дверь убрана: строкиЛиста без «сдаться»');

  // 4. Дверь вернули — строка снова на месте (игра может передумать).
  с.двери.сдаться = { действие: function () { вызовов++; } };
  с.управление.открыть();
  надо(видимыеСтроки(с).pop() === 'кнопка-лист-игры-сдаться', 'дверь вернули: строка снова последняя');

  // 5. «видна()» отвечает «нет» — строки нет (игрок уже выбыл).
  let можно = false;
  const в = собрать(путьКЛисту, { сдаться: { действие: function () {}, видна: function () { return можно; } } }, false);
  в.управление.открыть();
  надо(JSON.stringify(видимыеСтроки(в)) === JSON.stringify(былоВДереве), 'видна() = нет: строки нет');
  можно = true;
  в.управление.открыть();
  надо(видимыеСтроки(в).pop() === 'кнопка-лист-игры-сдаться', 'видна() = да: строка последняя');

  // 6. Дверь без действия — не дверь: строки нет.
  const пустая = собрать(путьКЛисту, { сдаться: {} }, false);
  пустая.управление.открыть();
  надо(JSON.stringify(видимыеСтроки(пустая)) === JSON.stringify(былоВДереве), 'дверь без действия: строки нет');

  // 7. «Во весь экран» тоже в конце листа — «Сдаться» всё равно ниже всех, в любом порядке появления.
  const т1 = собрать(путьКЛисту, { сдаться: { действие: function () {} } }, true);
  т1.управление.открыть();
  const порядок1 = т1.разметка.колонка.children.filter(function (у) { return у.classList.contains('лист-ещё__строка') && !у.classList.contains('скрыт'); });
  надо(порядок1.length === былоВДереве.length + 2, 'с «Во весь экран»: строк на две больше (' + порядок1.length + ')');
  надо(порядок1.length > 0 && порядок1[порядок1.length - 1].id === 'кнопка-лист-игры-сдаться', 'с «Во весь экран»: «Сдаться» последняя');
  надо(порядок1.length > 1 && порядок1[порядок1.length - 2].textContent === 'Во весь экран', 'с «Во весь экран»: она прямо над «Сдаться»');
  const т2 = собрать(путьКЛисту, {}, true);
  т2.управление.открыть();             // «Во весь экран» создана первой
  т2.двери.сдаться = { действие: function () {} };
  т2.управление.открыть();             // «Сдаться» появилась позже
  const порядок2 = т2.разметка.колонка.children.filter(function (у) { return у.classList.contains('лист-ещё__строка') && !у.classList.contains('скрыт'); });
  надо(порядок2.length > 0 && порядок2[порядок2.length - 1].id === 'кнопка-лист-игры-сдаться', 'дверь пришла позже «Во весь экран»: «Сдаться» всё равно последняя');

  // 8. «Во весь экран» появляется ПОЗЖЕ готовой «Сдаться» (был полный экран, потом обычный):
  //    она встаёт выше «Сдаться», а не после неё.
  const т3 = собрать(путьКЛисту, { сдаться: { действие: function () {} } }, true);
  т3.экран.полный = true;
  т3.управление.открыть();             // строки «Во весь экран» ещё нет, «Сдаться» уже есть
  надо(т3.документ.getElementById('кнопка-лист-игры-сдаться') !== null, 'полный экран: «Сдаться» уже создана');
  т3.управление.закрыть(false);
  т3.экран.полный = false;
  т3.управление.открыть();
  const порядок3 = т3.разметка.колонка.children.filter(function (у) { return у.classList.contains('лист-ещё__строка') && !у.classList.contains('скрыт'); });
  надо(порядок3.length === былоВДереве.length + 2, 'полный экран снят: строк на две больше (' + порядок3.length + ')');
  надо(порядок3.length > 0 && порядок3[порядок3.length - 1].id === 'кнопка-лист-игры-сдаться', 'полный экран снят: «Сдаться» последняя');
  надо(порядок3.length > 1 && порядок3[порядок3.length - 2].textContent === 'Во весь экран', 'полный экран снят: «Во весь экран» прямо над «Сдаться»');

  // 9. Лист закрывается ДО действия (плашку подтверждения экран покажет поверх чистого экрана).
  let былОткрыт = null;
  const з = собрать(путьКЛисту, {}, false);
  з.двери.сдаться = { действие: function () { былОткрыт = з.управление.открыт(); } };
  з.управление.открыть();
  нажатьСтрокуСдаться(з);
  надо(былОткрыт === false, 'внутри действия лист уже закрыт (открыт() = ' + былОткрыт + ')');

  // 10. Действие бросило ошибку — лист всё равно закрыт.
  const б = собрать(путьКЛисту, { сдаться: { действие: function () { throw new Error('сбой двери'); } } }, false);
  б.управление.открыть();
  try { нажатьСтрокуСдаться(б); } catch (ошибка) { /* сбой двери наружу — дело игры */ }
  надо(б.управление.открыт() === false, 'действие бросило: лист всё равно закрыт');

  // 11. Игрок выбыл при открытом листе: дверь пропала, нажатие прячет строку и закрывает лист.
  let позвали = 0;
  const в2 = собрать(путьКЛисту, { сдаться: { действие: function () { позвали++; } } }, false);
  в2.управление.открыть();
  в2.двери.сдаться = null;
  нажатьСтрокуСдаться(в2);
  const узел2 = в2.документ.getElementById('кнопка-лист-игры-сдаться');
  надо(узел2 !== null && узел2.classList.contains('скрыт'), 'двери нет при нажатии: строка спрятана');
  надо(в2.управление.открыт() === false, 'двери нет при нажатии: лист закрыт, а не молчит');
  надо(позвали === 0, 'двери нет при нажатии: действие не зовётся');

  console.log('Итого проверок: ' + итоги.всего + ', провалов: ' + итоги.провалов);
  return итоги;
}

