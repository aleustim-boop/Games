// Проверка: красная строка «Сдаться» в общем листе «⋯» (js/лист-ещё.js),
// этап Б7 игры «Захват» (штаб/игры/первая-игра/этапы.md).
//
// Запуск:
//   node tests/лист-ещё-сдаться.js                — обычный прогон, ждём 0 провалов
//   node tests/лист-ещё-сдаться.js --лист <путь>  — тот же набор на копии листа по пути
//   node tests/лист-ещё-сдаться.js --сломать      — ломающие запуски: каждая порча копии
//     листа (во временной папке) обязана покраснеть; файл проекта не трогаем
//
// Страницы нет: лист грузится в песочницу vm с поддельным документом из
// tests/поддельный-браузер.js. Ноль найденных узлов — провал, не пропуск.

