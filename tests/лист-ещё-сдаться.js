function сломать() {
  const временная = fs.mkdtempSync(path.join(os.tmpdir(), 'лист-сдаться-'));
  const исходник = fs.readFileSync(ФАЙЛ_ЛИСТА, 'utf8');
  const итоги = { всего: 0, провалов: 0 };
  try {
    ПОРЧИ.forEach(function (порча) {
      итоги.всего++;
      if (!исходник.includes(порча[1])) {
        итоги.провалов++;
        console.log('  ПРОВАЛ: порча «' + порча[0] + '» — нечего портить (нашлось 0 мест): проверка устарела');
        return;
      }
      const копия = path.join(временная, 'лист-ещё.js');
      fs.writeFileSync(копия, исходник.replace(порча[1], порча[2]));
      const запуск = spawnSync(process.execPath, [__filename, '--лист', копия], { encoding: 'utf8' });
      const покраснела = запуск.status === 1;
      console.log('  порча «' + порча[0] + '»: ' + (покраснела ? 'краснеет, как и должно' : 'НЕ покраснела (код ' + запуск.status + ')'));
      if (!покраснела) итоги.провалов++;
    });
  } finally {
    fs.rmSync(временная, { recursive: true, force: true });
  }
  console.log('Итого проверок: ' + итоги.всего + ', провалов: ' + итоги.провалов);
  return итоги;
}

const результат = process.argv.includes('--сломать') ? сломать() : прогнать(довод('--лист') || ФАЙЛ_ЛИСТА);
process.exit(результат.провалов > 0 ? 1 : 0);
