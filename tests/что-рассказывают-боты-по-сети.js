/** Имя карты так, как её называет сама игра: «7♦». */
function имяКарты(карта) {
  return карта ? правила.названиеКарты(карта) : '';
}

/* Как выглядит имя карты в тексте: достоинство и следом масть.
   Список достоинств и мастей спрашиваем у игры — своего здесь нет. */
const ОБРАЗЕЦ_КАРТЫ = new RegExp(
  '(?:' + правила.ВСЕ_ДОСТОИНСТВА.join('|') + ')[' + правила.МАСТИ.join('') + ']', 'g');

/** Все имена карт, названные в тексте. */
function картыВТексте(текст) {
  return String(текст || '').match(ОБРАЗЕЦ_КАРТЫ) || [];
}

/** Образец фразы: имена карт заменены на «К», числа — на «N». */
function образецФразы(текст, имена) {
  let т = String(текст || '');
  for (const имя of имена) {
    // Имя игрока в начале фразы заменяем на «ИМЯ»: имена у всех разные.
    if (имя && т.indexOf(имя) === 0) { т = 'ИМЯ' + т.slice(имя.length); break; }
  }
  /* Число и склонённое слово «карта» сводим к одному виду: «2 карты»
     и «5 карт» — это одна и та же фраза, а не две разные. Само склонение
     проверяется не здесь, а в «самая-длинная-подсказка.js». */
  return т.replace(ОБРАЗЕЦ_КАРТЫ, 'К')
          .replace(/\d+ карт(ы|у)?/g, 'N карт*')
          .replace(/\d+/g, 'N');
}

/* --------------------------------------------------------------------
   Разговор с сервером
   -------------------------------------------------------------------- */

function запрос(путь, тело, ждатьМс) {
  return new Promise(function (готово, беда) {
    const текст = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const обращение = http.request({
      host: ХОСТ, port: ПОРТ, method: 'POST', path: encodeURI(путь),
      headers: { 'Content-Type': 'application/json', 'Content-Length': текст.length }
    }, function (ответ) {
      let куски = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (к) { куски += к; });
      ответ.on('end', function () {
        let данные = {};
        try { данные = JSON.parse(куски); } catch (сбой) { данные = { сыройОтвет: куски }; }
        готово({ номер: ответ.statusCode, данные: данные });
      });
    });
    обращение.setTimeout(ждатьМс || 20000, function () {
      обращение.destroy(new Error('сервер не ответил на ' + путь + ' вовремя'));
    });
    обращение.on('error', беда);
    обращение.end(текст);
  });
}

/** Отвечает ли сервер вообще (дверь «здоровье» открывается обычным GET). */
function новыйЛиСервер() {
  return new Promise(function (готово) {
    const обращение = http.get({ host: ХОСТ, port: ПОРТ, path: encodeURI('/здоровье') }, function (ответ) {
      ответ.resume();
      готово(ответ.statusCode === 200);
    });
    обращение.setTimeout(5000, function () { обращение.destroy(); готово(false); });
    обращение.on('error', function () { готово(false); });
  });
}

/* --------------------------------------------------------------------
   Живой игрок: всё, что он знает, он узнал из ответов сервера
   -------------------------------------------------------------------- */

class Игрок {
  constructor(имя, код, пропуск, вид) {
    this.имя = имя;
    this.код = код;
    this.пропуск = пропуск;
    this.вид = вид || null;

    /* Что этот игрок ВИДЕЛ открытым за всю партию: карты со стола,
       карты своей руки и открытая козырная. Всё, что названо в рассказе
       и чего здесь нет, — чужая карта. */
    this.виделОткрытым = new Set();
    /* Карты нынешнего подхода: набирается, пока стол не пуст, и обнуляется,
       когда стол опустел. По нему видно, не назвали ли карту из прошлого. */
    this.столПодхода = new Set();
    /* Стол прошлого подхода — тот, который только что уехал. Именно про него
       говорит рассказ о «Бито» и о заборе карт. */
    this.уехавшийСтол = new Set();
    this.рукаБыла = null;      // сколько карт было в руке в прошлом виде
    this.разобрано = 0;        // сколько рассказов прочитано
  }

  /** Запомнить всё открытое из нового вида и обновить память о подходе. */
  впитать(вид) {
    if (!вид) return;
    const наСтоле = [];
    for (const пара of (вид.стол || [])) {
      if (пара.атака) наСтоле.push(имяКарты(пара.атака));
      if (пара.защита) наСтоле.push(имяКарты(пара.защита));
    }
    if (наСтоле.length === 0 && this.столПодхода.size > 0) {
      // Стол опустел — подход кончился, его карты уехали.
      this.уехавшийСтол = this.столПодхода;
      this.столПодхода = new Set();
    }
    for (const имя of наСтоле) { this.виделОткрытым.add(имя); this.столПодхода.add(имя); }
    for (const карта of (вид.мояРука || [])) this.виделОткрытым.add(имяКарты(карта));
    if (вид.козырнаяКарта) this.виделОткрытым.add(имяКарты(вид.козырнаяКарта));
  }

  async обновить() {
    const о = await запрос('/состояние', { код: this.код, пропуск: this.пропуск });
    if (о.номер !== 200) { пожаловаться(this.имя + ': сервер не отдал состояние', 'код ' + о.номер); return null; }
    this.принять(о.данные.состояние);
    return this.вид;
  }

  async ход(намерение) {
    const о = await запрос('/ход', Object.assign({ код: this.код, пропуск: this.пропуск }, намерение));
    if (о.номер !== 200) { пожаловаться(this.имя + ': сервер ответил на ход кодом ' + о.номер, JSON.stringify(намерение)); return null; }
    if (о.данные.состояние) this.принять(о.данные.состояние);
    return о.данные;
  }

  чтоНового(версия, ждать) {
    return запрос('/что-нового',
      { код: this.код, пропуск: this.пропуск, версия: версия }, ждать || 30000);
  }

  выйти() { return запрос('/выйти', { код: this.код, пропуск: this.пропуск }); }

  /* Новый вид: сперва разбираем рассказ (пока память ещё про прошлый вид),
     потом впитываем сам вид. Порядок важен: «вы добрали N» сверяется
     с рукой, какой она была ДО этого вида. */
  принять(вид) {
    if (!вид) return;
    разобратьРассказ(this, вид);
    this.впитать(вид);
    this.рукаБыла = (вид.мояРука || []).length;
    this.вид = вид;
  }
}

/* --------------------------------------------------------------------
   Разбор рассказа — здесь и живут все пять обещаний
   -------------------------------------------------------------------- */

/** Имена всех, кто сидит за столом (по «застолом»). */
function именаЗаСтолом(вид) {
  return (вид.застолом || []).map(function (м) { return м.имя || ''; });
}

/** Место, о котором рассказ: ищем по имени в начале фразы. */
function проКого(вид, текст) {
  let найдено = null;
  for (const м of (вид.застолом || [])) {
    const имя = м.имя || '';
    if (имя && String(текст).indexOf(имя) === 0) {
      if (!найдено || имя.length > (найдено.имя || '').length) найдено = м;
    }
  }
  return найдено;
}

function разобратьРассказ(игрок, вид) {
  const текст = вид && typeof вид.событие === 'string' ? вид.событие : '';
  if (!текст) return;
  // Один и тот же рассказ приходит с каждым видом, пока не случится новое
  // событие. Разбираем только новые — по номеру события.
  const номер = Number.isInteger(вид.номерСобытия) ? вид.номерСобытия : null;
  if (номер !== null && номер === игрок.прошлыйНомер) return;
  игрок.прошлыйНомер = номер;
  игрок.разобрано++;

  const названные = картыВТексте(текст);
  const своё = текст.indexOf('Вы ') === 0 || текст.indexOf('Вы,') === 0;
  const про = проКого(вид, текст);
  const вид_события = вид.видСобытия || '';

  /* Обещание 1: ни одной чужой карты. Карта, названная в рассказе, обязана
     быть той, которую этот игрок уже видел открытой. Стол нового вида
     впитывается ПОСЛЕ разбора, поэтому смотрим и на него тоже: рассказ
     про только что положенную карту приходит вместе с ней. */
  const открытоСейчас = new Set(игрок.виделОткрытым);
  for (const пара of (вид.стол || [])) {
    if (пара.атака) открытоСейчас.add(имяКарты(пара.атака));
    if (пара.защита) открытоСейчас.add(имяКарты(пара.защита));
  }
  for (const карта of (вид.мояРука || [])) открытоСейчас.add(имяКарты(карта));
  if (вид.козырнаяКарта) открытоСейчас.add(имяКарты(вид.козырнаяКарта));

  for (const имя of названные) {
    проверок++;
    if (!открытоСейчас.has(имя)) {
      пожаловаться('рассказ назвал карту, которой игрок не видел открытой (чужая рука или колода)',
        игрок.имя + ': «' + текст + '»; карта ' + имя);
    }
  }

  /* Обещание 2: забранное поимённо — только забравшему. */
  if (вид_события === 'забрал' && !своё) {
    проверок++;
    if (названные.length > 0) {
      пожаловаться('в рассказе о ЧУЖОМ заборе стола названы карты поимённо',
        игрок.имя + ': «' + текст + '»');
    }
  }

  /* Обещание 3: рассказ о конце подхода — про тот стол, который уехал. */
  if ((вид_события === 'бито' || вид_события === 'забрал') && названные.length > 0) {
    const уехал = игрок.столПодхода.size > 0 ? игрок.столПодхода : игрок.уехавшийСтол;
    for (const имя of названные) {
      проверок++;
      if (!уехал.has(имя)) {
        пожаловаться('рассказ о конце подхода назвал карту НЕ с того стола, что уехал',
          игрок.имя + ': «' + текст + '»; карта ' + имя +
          '; на столе лежало: [' + [...уехал].join(' ') + ']');
      }
    }
  }

  /* Обещание 4: «вы добрали N» сверяем с тем, как выросла рука. */
  const проДобор = /, вы добрали (\d+)$/.exec(текст);
  if (проДобор && игрок.рукаБыла !== null) {
    const сказано = Number(проДобор[1]);
    const стало = (вид.мояРука || []).length;
    /* Если стол забрал я сам — часть прироста это карты со стола.
       Сколько их было, знаю по своей же памяти о подходе. */
    const взятоСоСтола = (вид_события === 'забрал' && своё)
      ? (игрок.столПодхода.size > 0 ? игрок.столПодхода.size : игрок.уехавшийСтол.size)
      : 0;
    const насамомделе = стало - игрок.рукаБыла - взятоСоСтола;
    проверок++;
    if (сказано !== насамомделе) {
      пожаловаться('«вы добрали N» не сходится с тем, насколько выросла рука',
        игрок.имя + ': «' + текст + '»; сказано ' + сказано +
        ', на деле ' + насамомделе + ' (рука ' + игрок.рукаБыла + '→' + стало +
        ', со стола взято ' + взятоСоСтола + ')');
    }
    счёт.доборовСверено++;
  }

  /* Обещание 5: собираем образцы фраз отдельно про ботов и про живых. */
  if (!своё && про) {
    const образец = образецФразы(текст, именаЗаСтолом(вид));
    const куда = про.этоБот ? счёт.образцыБотов : счёт.образцыЖивых;
    if (!куда[образец]) куда[образец] = 0;
    куда[образец]++;
  }

  /* И заодно считаем главное: рассказывают ли вообще картами. */
  if (МОЖНО_НАЗВАТЬ.has(вид_события)) {
    счёт.можноНазвать++;
    const естьЧисло = /\d/.test(текст);
    if (названные.length > 0 || естьЧисло) счёт.сКартами++;
    else {
      счёт.безКарт++;
      if (счёт.примерыБезКарт.length < 5) счёт.примерыБезКарт.push(текст);
    }
    if (про && про.этоБот) {
      счёт.ходовБотов++;
      if (названные.length > 0 || естьЧисло) счёт.ходовБотовСКартами++;
      else счёт.ходовБотовБезКарт++;
    }
  }
}

/* События, о которых МОЖНО рассказать картами или числами. */
const МОЖНО_НАЗВАТЬ = new Set(['ход', 'подкинул', 'отбил', 'перевёл', 'бито', 'забрал']);

const счёт = {
  партий: 0, действий: 0, разобрано: 0,
  можноНазвать: 0, сКартами: 0, безКарт: 0, примерыБезКарт: [],
  ходовБотов: 0, ходовБотовСКартами: 0, ходовБотовБезКарт: 0,
  доборовСверено: 0,
  образцыБотов: {}, образцыЖивых: {}
};

/* --------------------------------------------------------------------
   Как ходит наш живой игрок: только по тому, что видит
   -------------------------------------------------------------------- */

async function походить(игрок) {
  const вид = игрок.вид;
  if (!вид || вид.завершена || !вид.яХожу) return false;

  if (вид.фаза === 'защита') {
    // Иногда переводим ход — так проверяется и рассказ о переводе.
    if (вид.могуПеревести && Math.random() < 0.4) {
      for (let к = 0; к < вид.мояРука.length; к++) {
        const ответ = await игрок.ход({ действие: 'перевести', карта: к });
        if (ответ && ответ.принято) return true;
      }
    }
    for (let п = 0; п < вид.стол.length; п++) {
      if (вид.стол[п].защита) continue;
      for (let к = 0; к < вид.мояРука.length; к++) {
        if (!правила.бьёт(вид.мояРука[к], вид.стол[п].атака, вид.козырь)) continue;
        const ответ = await игрок.ход({ действие: 'отбить', пара: п, карта: к });
        if (ответ && ответ.принято) return true;
      }
    }
    const беру = await игрок.ход({ действие: 'беру' });
    return Boolean(беру && беру.принято);
  }

  // Нападение или подкидывание
  for (let к = 0; к < вид.мояРука.length; к++) {
    const ответ = await игрок.ход({ действие: 'ходить', карта: к });
    if (ответ && ответ.принято) return true;
  }
  const бито = await игрок.ход({ действие: 'бито' });
  return Boolean(бито && бито.принято);
}

/* --------------------------------------------------------------------
   Одна партия за одним столом
   -------------------------------------------------------------------- */

async function сыгратьПартию(стол, номер) {
  const создание = await запрос('/создать', {
    мест: стол.мест, переводной: стол.переводной, парами: стол.парами, имя: 'Первый'
  });
  if (создание.номер !== 200 || !создание.данные.код) {
    пожаловаться('сервер не создал комнату', 'код ответа ' + создание.номер);
    return;
  }
  const код = создание.данные.код;
  const игроки = [new Игрок('Первый', код, создание.данные.пропуск, создание.данные.состояние)];

  for (let н = 1; н < стол.живых; н++) {
    const имя = ['Второй', 'Третий', 'Четвёртый'][н - 1];
    const вход = await запрос('/войти', { код: код, имя: имя });
    if (вход.номер !== 200 || !вход.данные.пропуск) {
      пожаловаться('живой игрок не смог войти по коду', имя + ', код ответа ' + вход.номер);
      return;
    }
    игроки.push(new Игрок(имя, код, вход.данные.пропуск, вход.данные.состояние));
  }

  // Оставшиеся места занимают боты — их сажает хозяин.
  for (let н = стол.живых; н < стол.мест; н++) {
    const ответ = await игроки[0].ход({ действие: 'бот' });
    if (!ответ || !ответ.принято) {
      пожаловаться('хозяин не смог посадить бота', 'место ' + (н + 1) +
        ((ответ && ответ.причина) ? ': ' + ответ.причина : ''));
      return;
    }
  }

  const пуск = await игроки[0].ход({ действие: 'начать' });
  if (!пуск || !пуск.принято) {
    пожаловаться('партия не началась по кнопке «Начать»',
      (пуск && пуск.причина) ? пуск.причина : 'сервер промолчал');
    return;
  }

  for (const и of игроки) await и.обновить();

  /* Играем, пока партия не кончится. Все живые всё время спрашивают
     новости: так каждый читает СВОЙ рассказ, и «вы добрали» проверяется
     у каждого своё. Боты ходят на сервере сами, по таймеру. */
  let действий = 0;
  let тишины = 0;      // сколько кругов подряд НИЧЕГО не произошло
  let прошлаяВерсия = игроки[0].вид ? игроки[0].вид.версия : null;
  while (!игроки[0].вид.завершена && действий < ПОТОЛОК_ДЕЙСТВИЙ && тишины < ТЕРПЕНИЕ) {
    let сделали = false;
    for (const и of игроки) {
      if (и.вид && и.вид.яХожу && !и.вид.завершена) {
        if (await походить(и)) { сделали = true; действий++; }
      }
    }
    // Всех обновляем: каждый должен прочитать свой рассказ о том же событии.
    for (const и of игроки) await и.обновить();
    /* «Тишина» — это когда не сходили ни мы, ни боты. Ход бота виден
       по версии комнаты: она растёт на каждое событие. Без этой проверки
       длинная череда ходов ботов (каждый с паузой в 0,7 секунды) выглядела
       бы зависанием — и проверка врала бы про исправную игру. */
    const версия = игроки[0].вид ? игроки[0].вид.версия : null;
    if (сделали || версия !== прошлаяВерсия) тишины = 0;
    else тишины++;
    прошлаяВерсия = версия;
    if (!сделали) await пауза(120);   // ждём ход бота на сервере
  }

  счёт.действий += действий;
  if (!игроки[0].вид.завершена) {
    пожаловаться('партия не доигралась до конца',
      стол.имя + ', партия ' + номер + ': действий ' + действий + ', тишины ' + тишины);
  }
  счёт.партий++;
  for (const и of игроки) счёт.разобрано += и.разобрано;

  for (const и of игроки) await и.выйти();
}

