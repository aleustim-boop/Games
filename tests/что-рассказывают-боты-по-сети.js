/* =====================================================================
   ЧТО РАССКАЗЫВАЮТ БОТЫ ПО СЕТИ — проверка через НАСТОЯЩИЙ сервер.

   ЗАЧЕМ ЕЩЁ ОДНА ПРОВЕРКА. Рядом уже лежит «рассказ-о-ходе-по-сети.js»:
   он поднимает комнату прямо внутри себя, без сети, и потому видит каждое
   событие. Эта смотрит с другой стороны — глазами живого игрока: она
   разговаривает с уже запущенным сервером обычными запросами по HTTP
   и знает ровно то, что сервер ей прислал. Ничего, кроме ответов сервера,
   у неё нет — как и у страницы в телефоне.

   Так проверяется вся дорога целиком: правила → партия на сервере →
   «видДляИгрока» → комната → HTTP → игрок. Если чужая карта протечёт
   где-нибудь по пути, здесь это будет видно, даже когда внутри всё чисто.

   ЧТО ПРОВЕРЯЕТСЯ

     1. НИ ОДНОЙ ЧУЖОЙ КАРТЫ. Каждая карта, названная в рассказе, обязана
        быть той, которую этот игрок и так видел своими глазами: она лежала
        на открытом столе, или лежит у него в руке, или это открытая
        козырная карта под колодой. Всё остальное — утечка: карта из чужой
        руки или из колоды.

     2. ЗАБРАННОЕ — ТОЛЬКО ЗАБРАВШЕМУ. Когда стол забирает другой игрок,
        в рассказе про него не должно быть НИ ОДНОГО имени карты — только
        число. Поимённо забранное называют лишь тому, кто забрал сам.

     3. РАССКАЗ ПРО ЭТОТ ПОДХОД, А НЕ ПРО ПРОШЛЫЙ. Имена карт в рассказе
        о конце подхода обязаны быть с того стола, который только что уехал,
        а не с позапрошлого.

     4. ДОБОР У КАЖДОГО СВОЙ. Приписка «, вы добрали N» сверяется с тем,
        насколько на самом деле выросла рука ЭТОГО игрока (за вычетом карт,
        которые он забрал со стола).

     5. БОТ И ЖИВОЙ РАССКАЗЫВАЮТСЯ ОДИНАКОВО. Из каждой фразы вынимается
        её образец (имена карт заменяются на «К», числа на «N»), и образцы,
        встретившиеся про ботов, сравниваются с образцами про живых. Фраза,
        которая бывает только про бота или только про живого, — находка:
        внутри одной партии человек не должен читать про разное разными
        словами.

   Ни одна фраза сюда не переписана. Ожидания считаются по ответам сервера
   (стол, руки, число карт), а имена карт и склонение слова «карта» берутся
   у самой игры (js/game.js).

   ЗАПУСК (сервер комнат должен быть уже поднят):
       node tests/что-рассказывают-боты-по-сети.js
       node tests/что-рассказывают-боты-по-сети.js 8790 6
   Первое число — порт сервера комнат, второе — сколько партий сыграть.
   ===================================================================== */

