/* Ждём письма не наугад, а по числу. Пауза между письмами — из самого
   модуля. Дождались нужного числа — ждём ещё ТИШИНУ (три паузы): не
   придёт ли лишнее письмо (на этом краснеет «--сломать»). Потолок —
   чтобы не висеть, если письмо не придёт вовсе. */
const ТЕКСТ_МОДУЛЯ = fs.readFileSync(path.join(КОРЕНЬ, 'server', 'итог-в-бот.js'), 'utf8');
const найденаПауза = ТЕКСТ_МОДУЛЯ.match(/const ПАУЗА_МЕЖДУ_ПИСЬМАМИ = (\d+);/);
const ПАУЗА_ПИСЕМ = найденаПауза ? Number(найденаПауза[1]) : 0;
const ТИШИНА = ПАУЗА_ПИСЕМ * 3;
const ПОТОЛОК_ЖДАТЬ = 5000;
/* Сколько шло контрольное письмо (сверка А): столько же ждём там, где
   писем быть не должно, — иначе «ноль» мог бы значить «ещё не дошло». */
let контрольноеВремя = 0;

/** Дождаться, пока после отметки уйдёт сколько писем и настанет тишина; вернуть, сколько ждали (мс). */
async function дождатьсяПисем(отметка, сколько) {
  const начало = Date.now();
  let число = писемПосле(отметка);
  let перемена = начало;
  while (Date.now() - начало < ПОТОЛОК_ЖДАТЬ) {
    await пауза(10);
    const сейчас = писемПосле(отметка);
    if (сейчас !== число) { число = сейчас; перемена = Date.now(); }
    if (число >= сколько && Date.now() - перемена >= ТИШИНА) break;
  }
  return Date.now() - начало;
}

/** Там, где писем быть не должно: ждём столько же, сколько шло контрольное письмо. */
function ждатьКакКонтрольное() {
  return пауза(контрольноеВремя);
}

/** Место в событии по номеру Telegram. */
function местоПоНомеру(событие, номер) {
  return событие ? событие.места.find(function (м) { return м.номер === номер; }) || null : null;
}

/** Сверить письмо с тем, что модуль собирает из того же события. */
function сверитьПисьмо(запись, событие, номер, что) {
  const место = местоПоНомеру(событие, номер);
  const ждём = место ? итогВБот.собратьПисьмо(событие, место) : null;
  проверить(Boolean(запись && ждём) && запись.тело.text === ждём.текст,
    что + ': текст как у модуля' + (ждём ? ' («' + ждём.текст.replace(/\n/g, ' / ') + '»)' : ' — места нет'));
  проверить(Boolean(запись && ждём) && JSON.stringify(запись.тело.reply_markup) === JSON.stringify(ждём.кнопки),
    что + ': кнопки как у модуля');
  const кнопки = запись && запись.тело.reply_markup ? запись.тело.reply_markup.inline_keyboard[0] || [] : [];
  const играть = кнопки.find(function (к) { return к.web_app; });
  проверить(Boolean(играть) && typeof играть.web_app.url === 'string' && играть.web_app.url.indexOf(АДРЕС_ИГРЫ + '/') === 0,
    что + ': web_app.url начинается с адреса игры (' + (играть ? играть.web_app.url : 'кнопки нет') + ')');
  проверить(кнопки.some(function (к) { return к.callback_data === итогВБот.ОТКАЗ_ОТ_ИТОГОВ; }),
    что + ': есть кнопка отказа от итогов');
}

