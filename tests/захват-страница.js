/** Содержимое всех блоков «@media (max-width: 359px) { … }» (скобки считаем сами). */
function блокиУзкогоЭкрана(css) {
  const блоки = [];
  const шаблон = /@media\s*\(max-width:\s*359px\)\s*\{/g;
  let м;
  while ((м = шаблон.exec(css))) {
    let глубина = 1;
    let i = м.index + м[0].length;
    while (i < css.length && глубина > 0) {
      if (css[i] === '{') глубина++;
      else if (css[i] === '}') глубина--;
      i++;
    }
    блоки.push(css.slice(м.index + м[0].length, i - 1));
  }
  return блоки;
}

/** Заменить n-е (с 1) вхождение подстроки. */
function заменитьН(текст, что, чем, н) {
  let поз = -1;
  for (let k = 0; k < н; k++) {
    поз = текст.indexOf(что, поз + 1);
    if (поз < 0) return текст;
  }
  return текст.slice(0, поз) + чем + текст.slice(поз + что.length);
}

/** Тело правила «селектор { … }» из css (одно, от начала строки); пусто, если нет. */
function правилоCss(css, селектор) {
  const м = new RegExp('(^|\\n)' + селектор.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\s*\\{([^}]*)\\}').exec(css);
  return м ? м[2] : '';
}

/** Блок @media широкого окна: заголовок, содержимое и остаток css без него (скобки считаем сами). */
function разобратьШирокоеОкно(css) {
  const м = /@media[^{]*min-aspect-ratio:\s*10\/13[^{]*\{/.exec(css);
  if (!м) return { найдено: false, заголовок: '', внутри: '', снаружи: css };
  let глубина = 1;
  let i = м.index + м[0].length;
  while (i < css.length && глубина > 0) {
    if (css[i] === '{') глубина++;
    else if (css[i] === '}') глубина--;
    i++;
  }
  return {
    найдено: true, заголовок: м[0], внутри: css.slice(м.index + м[0].length, i - 1),
    снаружи: css.slice(0, м.index) + css.slice(i)
  };
}

