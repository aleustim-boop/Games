const fs = require('fs');
const os = require('os');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ИМЯ_СТРАНИЦЫ = 'захват.html';

/** Кусок разметки от открывающего тега, начавшегося с позиции начало, до его закрывающего (считаем вложенные того же тега). */
function элементС(текст, начало) {
  const тег = /^<([a-z0-9]+)/i.exec(текст.slice(начало));
  if (!тег) return '';
  const шаблон = new RegExp('<(/?)' + тег[1] + '(?=[\\s>/])', 'gi');
  шаблон.lastIndex = начало;
  let глубина = 0;
  let м;
  while ((м = шаблон.exec(текст))) {
    глубина += м[1] ? -1 : 1;
    if (глубина === 0) return текст.slice(начало, текст.indexOf('>', м.index) + 1);
  }
  return '';
}

/** Элемент разметки с заданным id (целиком, с содержимым); пусто, если такого нет. */
function элементПоId(текст, id) {
  const м = new RegExp('<[a-z0-9]+[^>]*\\sid="' + id + '"').exec(текст);
  return м ? элементС(текст, м.index) : '';
}

/** Все id, которые ищет код игры (getElementById и $('…') в js/захват-*.js), и те, что код создаёт сам. */
function idКода() {
  const папка = path.join(КОРЕНЬ, 'js');
  const файлы = fs.readdirSync(папка).filter(ф => /\.js$/.test(ф));
  const ищут = new Set();
  const создаёт = new Set();
  файлы.forEach(ф => {
    const т = fs.readFileSync(path.join(папка, ф), 'utf8');
    if (/^захват-/.test(ф)) {
      for (const м of т.matchAll(/(?:getElementById|\$)\(\s*'([^']+)'\s*\)/g)) ищут.add(м[1]);
    }
    // узлы, которые код делает сам (в любом файле: окно знаков и плашку выхода делают общие модули)
    for (const м of т.matchAll(/(?:\.id\s*=|\bID_[А-ЯЁA-Z_]+\s*=)\s*'([^']+)'/g)) создаёт.add(м[1]);
    for (const м of т.matchAll(/новаяКнопка\(\s*'([^']+)'/g)) создаёт.add(м[1]);
  });
  return { ищут, создаёт };
}

/** Все проверки против заданных файлов страницы, реестра и витрины. */
function запустить(пути, подробно) {
  let проверок = 0;
  const провалы = [];
  function проверить(условие, что) {
    проверок++;
    if (!условие) { провалы.push(что); if (подробно) console.log('  ПРОВАЛ: ' + что); }
    else if (подробно) console.log('  ок   ' + что);
  }

  const страница = fs.readFileSync(пути.страница, 'utf8');
  const витрина = fs.readFileSync(пути.витрина, 'utf8');
  const реестрТекст = fs.readFileSync(пути.реестр, 'utf8');
  // Разметка без html-комментариев: закомментированное подключением не считается
  const разметка = страница.replace(/<!--[\s\S]*?-->/g, '');

  // 1) экраны и листы: без них страница-пустышка
  const нужныеId = [
    'экран-лобби', 'захват-настройки', 'экран-игры', 'экран-друга', 'экран-комнаты', 'экран-входа',
    'захват-игроки', 'захват-карта', 'захват-холст', 'захват-слой',
    'захват-отменить', 'захват-готово', 'кнопка-эмоции',
    'захват-приказ', 'захват-карточка', 'захват-журнал', 'захват-выбыл',
    'захват-справка', 'захват-итог', 'захват-рекорды', 'лист-игры'
  ];
  нужныеId.forEach(id => {
    проверить(new RegExp('id="' + id + '"').test(разметка), 'в странице есть id="' + id + '"');
  });
  // у каждого из шести мест — узел имени с номером места (к нему привязывается облачко фразы)
  for (let н = 1; н <= 6; н++) {
    проверить(new RegExp('id="захват-имя-' + н + '"[^>]*data-место="' + н + '"').test(разметка),
      'у места ' + н + ' есть узел имени с data-место');
  }
  // «Сказать» спрятана до партии по сети
  проверить(/id="кнопка-эмоции"[^>]*class="[^"]*скрыт/.test(разметка), '«Сказать» скрыта (её показывает онлайн)');
  // верхняя строка «‹ ⋯»
  проверить((разметка.match(/data-назад/g) || []).length >= 3, 'верхняя строка: кнопки «назад» есть на экранах');
  проверить((разметка.match(/data-меню/g) || []).length >= 3, 'верхняя строка: кнопки «⋯» есть на экранах');
  проверить((разметка.match(/class="верх-игры"/g) || []).length >= 3, 'верхние строки страницы — общий класс верх-игры (ноль — провал)');
  проверить(!/захват-верх/.test(разметка), 'класса захват-верх в странице нет');
  // нижняя полоса есть в лобби, на столе её нет
  const стол = /<section id="экран-игры"[\s\S]*?<\/section>/.exec(разметка);
  проверить(!!стол, 'раздел экран-игры найден');
  проверить(!!стол && !/нижние-вкладки/.test(стол[0]), 'на столе нет нижней полосы');
  // стол «Парящий» (этап П2): пульт, капсула раунда, «Сказать» без эмодзи, id кода — по одному разу
  const пульт = элементПоId(разметка, 'захват-пульт');
  проверить(пульт.length > 0, 'на столе есть #захват-пульт (ноль — провал)');
  const порядокПульта = ['id="захват-подсказка"', 'id="захват-готовы"', 'id="захват-чипы"', 'id="захват-пластина"', 'class="захват-панель-действий"']
    .map(п => пульт.indexOf(п));
  проверить(порядокПульта.every(и => и >= 0), 'в пульте есть подсказка, «Готовы», ряд чипов, пластина и панель действий');
  проверить(порядокПульта.every((и, i) => i === 0 || и > порядокПульта[i - 1]),
    'в пульте по порядку: подсказка, #захват-готовы, #захват-чипы, #захват-пластина, .захват-панель-действий');
  проверить(/id="захват-чипы"[^>]*role="list"/.test(пульт), '#захват-чипы — role="list"');
  проверить(/<div id="захват-пульт" class="захват-пульт стекло-панель"/.test(разметка), 'у пульта классы захват-пульт и стекло-панель');
  проверить(!!стол && стол[0].indexOf('id="захват-карта"') >= 0
    && стол[0].indexOf('id="захват-карта"') < стол[0].indexOf('class="верх-игры"'),
    'карта #захват-карта — первая в столе, раньше верхней строки');
  const капсулаРаунда = (/<div class="захват-раунд[^"]*"/.exec(разметка) || { index: -1 }).index;
  const капсулаТекст = капсулаРаунда >= 0 ? элементС(разметка, капсулаРаунда) : '';
  проверить(капсулаТекст.indexOf('id="захват-раунд"') >= 0, 'в капсуле раунда есть #захват-раунд (ноль — провал)');
  проверить(/стекло-капсула/.test(капсулаТекст.slice(0, капсулаТекст.indexOf('>'))), 'капсула раунда — класс стекло-капсула');
  const эмоции = элементПоId(разметка, 'кнопка-эмоции');
  проверить(эмоции.length > 0, 'кнопка «Сказать» найдена (ноль — провал)');
  проверить(!/[^\u0000-\u007FЀ-ӿ]/.test(эмоции), '«Сказать»: нет символов вне латиницы и кириллицы (эмодзи)');
  проверить(/aria-label="[^"]+"/.test(эмоции), '«Сказать»: есть aria-label');
  const код = idКода();
  проверить(код.ищут.size >= 50, 'код ищет не меньше 50 id (найдено ' + код.ищут.size + ', ноль — провал)');
  const сторонние = [];
  код.ищут.forEach(id => {
    if (код.создаёт.has(id)) return; // узел делает сам код, в разметке его нет
    const раз = (разметка.match(new RegExp('\\sid="' + id + '"', 'g')) || []).length;
    if (раз !== 1) сторонние.push(id + ' ×' + раз);
  });
  проверить(сторонние.length === 0, 'каждый id, который ищет код, есть в разметке ровно один раз; не так: ' + сторонние.join(', '));

  const лобби = /<section id="экран-лобби"[\s\S]*?<\/section>/.exec(разметка);
  проверить(!!лобби, 'раздел экран-лобби найден (ноль — провал)');
  проверить(!!лобби && /<nav class="нижние-вкладки"/.test(лобби[0]), 'внутри экран-лобби есть нижняя полоса');
  проверить(!!лобби && /data-назад/.test(лобби[0]), 'внутри экран-лобби есть кнопка «‹» (data-назад)');
  проверить(!!лобби && /data-меню/.test(лобби[0]), 'внутри экран-лобби есть кнопка «⋯» (data-меню)');
  // строки общего листа «⋯» в порядке
  const порядокЛиста = ['меню', 'правила', 'звук', 'вибрация', 'оформление', 'рекорды', 'закрыть']
    .map(к => разметка.indexOf('id="кнопка-лист-игры-' + к + '"'));
  проверить(порядокЛиста.every(и => и >= 0) && порядокЛиста.every((и, i) => i === 0 || и > порядокЛиста[i - 1]),
    'строки листа «⋯»: В меню · Как играть · Звук · Вибрация · Оформление · Рекорды · Закрыть');

  // 2) сеть.js ровно один раз и с версией витрины
  const сетьСтраницы = разметка.match(/<script[^>]+src="js\/сеть\.js(\?[^"]*)?"/g) || [];
  проверить(сетьСтраницы.length === 1, 'js/сеть.js подключён ровно один раз (найдено ' + сетьСтраницы.length + ')');
  const версияСтраницы = /src="js\/сеть\.js\?v=([^"]+)"/.exec(разметка);
  const версияВитрины = /src="js\/сеть\.js\?v=([^"]+)"/.exec(витрина);
  проверить(!!версияВитрины, 'в index.html найден js/сеть.js?v=');
  проверить(!!версияСтраницы && !!версияВитрины && версияСтраницы[1] === версияВитрины[1],
    'версия js/сеть.js на странице совпадает с index.html');

  // 3) порядок подключений
  const скрипты = [];
  const шаблонСкрипта = /<script[^>]+src="([^"?]+)(\?v=[^"]+)?"/g;
  let м;
  while ((м = шаблонСкрипта.exec(разметка))) скрипты.push({ файл: м[1], версия: м[2] });
  const место = файл => скрипты.findIndex(с => с.файл === файл);
  проверить(скрипты.length > 0, 'найдены подключения скриптов (ноль — провал)');
  проверить(место('js/игры-реестр.js') >= 0 && место('js/игры-реестр.js') < место('js/рейтинг-экран.js'),
    'js/игры-реестр.js подключён раньше js/рейтинг-экран.js');
  проверить(место('js/захват-знаки.js') >= 0 && место('js/захват-знаки.js') < место('js/деберц-сказать.js'),
    'js/захват-знаки.js подключён раньше js/деберц-сказать.js');
  // Игра по сети (В9а): модуль берёт стол у экрана и ставит мост ИграПоСети до того, как js/сеть.js его ищет.
  const онлайн = место('js/захват-онлайн.js');
  проверить(онлайн >= 0, 'подключён js/захват-онлайн.js (игра по сети)');
  проверить(онлайн >= 0 && место('js/онлайн-лобби.js') >= 0 && место('js/онлайн-лобби.js') < онлайн,
    'js/захват-онлайн.js подключён после js/онлайн-лобби.js');
  проверить(онлайн >= 0 && место('js/захват-экран.js') >= 0 && место('js/захват-экран.js') < онлайн,
    'js/захват-онлайн.js подключён после js/захват-экран.js (стол берёт у экрана)');
  проверить(онлайн >= 0 && место('js/сеть.js') > онлайн,
    'js/захват-онлайн.js подключён раньше js/сеть.js (мост ИграПоСети готов до сети)');
  ['карты', 'правила', 'бот', 'память', 'звук', 'знаки', 'раскрытие', 'карта-вид'].forEach(имя => {
    const файл = 'js/захват-' + имя + '.js';
    проверить(место(файл) >= 0, 'подключён файл игры ' + файл);
  });
  // каждый подключённый файл игры (скрипт или оформление): номер ?v= есть, подключён один раз, лежит на диске
  const подключённыеФайлы = скрипты.concat(
    (разметка.match(/<link[^>]+href="[^"]*"/g) || []).map(т => {
      const к = /href="([^"?]+)(\?v=[^"]+)?"/.exec(т);
      return { файл: к[1], версия: к[2] };
    })
  ).filter(с => /^js\/захват-/.test(с.файл) || /^style-захват\.css$/.test(с.файл));
  проверить(подключённыеФайлы.length > 0, 'найдены подключённые файлы игры (ноль — провал)');
  подключённыеФайлы.forEach(с => {
    проверить(!!с.версия, с.файл + ' — с номером ?v=');
    проверить(подключённыеФайлы.filter(д => д.файл === с.файл).length === 1, с.файл + ' — подключён ровно один раз');
    проверить(fs.existsSync(path.join(КОРЕНЬ, с.файл)), с.файл + ' — лежит на диске');
  });
  проверить(/<script[^>]+src="js\/популярность\.js[^"]*"[^>]*data-game="захват"/.test(разметка),
    'счётчик популярности назван «захват»');

  // 4) вид — только в файлах оформления
  проверить(!/\sstyle\s*=/.test(разметка), 'в разметке нет style=');
  проверить(!/#[0-9a-fA-F]{3,8}\b/.test(разметка.replace(/&#\d+;/g, '')), 'в разметке нет цветов вида #abc');
  проверить(!/rgba?\(|hsla?\(/.test(разметка), 'в разметке нет цветов rgb()/hsl()');
  проверить(!/<svg/i.test(разметка), 'в разметке нет <svg>');
  const рисунки = (разметка.match(/<img[^>]+src="([^"?]+)/g) || []).map(т => /src="([^"]+)/.exec(т)[1]);
  const чужие = рисунки.filter(р => р !== 'img/захват/лобби.webp' && !/^img\/дурак\/значки\//.test(р));
  проверить(рисунки.includes('img/захват/лобби.webp'), 'картинка-гнездо лобби: img/захват/лобби.webp');
  проверить(чужие.length === 0, 'других рисунков нет; лишние: ' + чужие.join(', '));

  // 4а) «Как играть» (ТЗ 8.8, правка 02.10) и режим «До победы» (этап Р6)
  const справка = элементПоId(разметка, 'захват-справка');
  проверить(справка.length > 0, 'лист «Как играть» найден (ноль — провал)');
  const карточкаПо = слово => (справка.match(/<p[^>]*>[\s\S]*?<\/p>/g) || []).find(п => п.indexOf('<strong>' + слово) >= 0) || '';
  проверить(карточкаПо('Все ходят разом').indexOf('«+N» — новые войска соперников') >= 0, 'карточка 2: объяснено «+N» соперников');
  проверить(карточкаПо('Подкрепление').indexOf('встаёт сразу') >= 0, 'карточка 3 «Подкрепление»: «встаёт сразу»');
  проверить(карточкаПо('Бой').indexOf('увести войска') >= 0, 'карточка 5 «Бой»: «увести войска»');
  const пояснение = элементПоId(разметка, 'захват-онлайн-раунды-пояснение');
  проверить(пояснение.length > 0, 'под рядом «Раундов» онлайн-лобби есть узел пояснения (ноль — провал)');
  проверить(/class="([^"]*\s)?скрыт(\s[^"]*)?"/.test(пояснение.slice(0, пояснение.indexOf('>'))) && /захват-тихо/.test(пояснение.slice(0, пояснение.indexOf('>'))),
    'пояснение «До победы» скрыто классом и серое (захват-тихо)');
  проверить(пояснение.indexOf('Не дольше 50 раундов') >= 0, 'пояснение: «Не дольше 50 раундов»');
  const рядРаундов = разметка.indexOf('id="захват-онлайн-раунды"');
  проверить(рядРаундов >= 0 && разметка.indexOf('id="захват-онлайн-раунды-пояснение"') > рядРаундов, 'пояснение стоит под рядом «Раундов»');

  // 5) скрытая запись реестра (читаем реестр так же, как браузер: скриптом)
  const окно = {};
  let игры = null;
  try {
    new Function('window', 'module', реестрТекст)(окно, { exports: {} });
    игры = окно.ИгрыРеестр && typeof окно.ИгрыРеестр.все === 'function' ? окно.ИгрыРеестр.все() : null;
  } catch (с) { игры = null; }
  проверить(Array.isArray(игры) && игры.length > 0, 'реестр прочитан и не пуст');
  const запись = (игры || []).find(и => и.ключ === 'захват');
  проверить(!!запись, 'в реестре есть запись «захват»');
  if (запись) {
    проверить(запись.страница === ИМЯ_СТРАНИЦЫ, 'у записи страница ' + ИМЯ_СТРАНИЦЫ);
    проверить(запись.вРейтинге === true, 'вРейтинге = true (рейтинг включён, этап Б11)');
    проверить(!('безРейтинга' in запись), 'у записи нет поля «безРейтинга»');
    проверить(запись.вес === 0.5, 'вес 0.5 (сейчас: ' + запись.вес + ')');
    const способы = Array.isArray(запись.способОчков) ? запись.способОчков : [];
    проверить(способы.length === 2 && способы.includes('сеть') && способы.includes('билет'),
      'способОчков: сеть и билет (сейчас: ' + способы.join(', ') + ')');
    const бот = запись.бот;
    проверить(!!бот && typeof бот === 'object', 'у записи есть поле «бот»');
    if (бот && typeof бот === 'object') {
      проверить(бот.партияНеКорочеСекунд === 60, 'бот: порог партии 60 с (сейчас: ' + бот.партияНеКорочеСекунд + ')');
      проверить(бот.билетЖивётЧасов === 3, 'бот: билет живёт 3 ч (сейчас: ' + бот.билетЖивётЧасов + ')');
      const уровни = бот.уровни && typeof бот.уровни === 'object' ? Object.keys(бот.уровни) : [];
      проверить(['лёгкий', 'обычный', 'сложный'].every(у => уровни.includes(у)) && уровни.length === 3,
        'бот: три уровня лёгкий/обычный/сложный (сейчас: ' + уровни.join(', ') + ')');
      проверить(бот.экран === 'js/захват-экран.js', 'бот: экран js/захват-экран.js (сейчас: ' + бот.экран + ')');
    }
    // server/билеты.js читает порог и билет только из «бот»: плоско они молча выключают билет
    проверить(!('партияНеКорочеСекунд' in запись) && !('билетЖивётЧасов' in запись),
      'порог и срок билета не лежат плоско в записи');
  }
  return { проверок, провалы };
}

