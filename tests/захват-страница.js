// ---------------------------------------------------------------- запуск

const аргументы = process.argv.slice(2);
const номерФлага = аргументы.indexOf('--сломать');

if (номерФлага < 0) {
  const итог = запустить({
    страница: path.join(КОРЕНЬ, ИМЯ_СТРАНИЦЫ),
    реестр: path.join(КОРЕНЬ, 'js', 'игры-реестр.js'),
    витрина: path.join(КОРЕНЬ, 'index.html')
  }, true);
  console.log('Итого проверок: ' + итог.проверок + ', провалов: ' + итог.провалы.length);
  process.exit(итог.провалы.length ? 1 : 0);
} else {
  const папка = аргументы[номерФлага + 1] || fs.mkdtempSync(path.join(os.tmpdir(), 'захват-страница-'));
  let всегоПроверок = 0;
  let всегоПровалов = 0;
  let непокраснели = 0;
  // Контроль: копия настоящей страницы без порчи обязана быть зелёной —
  // иначе покраснение порч ниже ничего не доказывает.
  const контроль = path.join(папка, 'контроль');
  fs.mkdirSync(контроль, { recursive: true });
  const путиКонтроля = { страница: path.join(контроль, ИМЯ_СТРАНИЦЫ), реестр: path.join(контроль, 'реестр.js'), витрина: path.join(контроль, 'index.html') };
  fs.writeFileSync(путиКонтроля.страница, fs.readFileSync(path.join(КОРЕНЬ, ИМЯ_СТРАНИЦЫ), 'utf8'));
  fs.writeFileSync(путиКонтроля.реестр, fs.readFileSync(path.join(КОРЕНЬ, 'js', 'игры-реестр.js'), 'utf8'));
  fs.writeFileSync(путиКонтроля.витрина, fs.readFileSync(path.join(КОРЕНЬ, 'index.html'), 'utf8'));
  const итогКонтроля = запустить(путиКонтроля, false);
  if (итогКонтроля.провалы.length) {
    непокраснели++;
    console.log('  КОНТРОЛЬ НЕ ЗЕЛЁНЫЙ (страница с подключённым захват-онлайн.js): ' + итогКонтроля.провалы.join('; '));
  } else console.log('  контроль зелёный: страница с подключённым захват-онлайн.js (' + итогКонтроля.проверок + ' проверок)');
  сломанныеКопии(папка).forEach(({ порча, пути }) => {
    if (порча.нетМеста) {
      непокраснели++;
      console.log('  НЕТ МЕСТА ДЛЯ ПОРЧИ (текст в файле изменился): ' + порча.имя);
      return;
    }
    const итог = запустить(пути, false);
    всегоПроверок += итог.проверок;
    всегоПровалов += итог.провалы.length;
    if (итог.провалы.length) console.log('  краснеет: ' + порча.имя + ' (провалов ' + итог.провалы.length + ')');
    else { непокраснели++; console.log('  НЕ КРАСНЕЕТ: ' + порча.имя); }
  });
  console.log('Итого проверок: ' + всегоПроверок + ', провалов: ' + всегоПровалов);
  process.exit(непокраснели ? 3 : 1);
}
