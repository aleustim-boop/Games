/** Кусок разметки от открывающего тега, начавшегося с позиции начало, до его закрывающего (считаем вложенные того же тега). */
function элементС(текст, начало) {
  const тег = /^<([a-z0-9]+)/i.exec(текст.slice(начало));
  if (!тег) return '';
  const шаблон = new RegExp('<(/?)' + тег[1] + '(?=[\\s>/])', 'gi');
  шаблон.lastIndex = начало;
  let глубина = 0;
  let м;
  while ((м = шаблон.exec(текст))) {
    глубина += м[1] ? -1 : 1;
    if (глубина === 0) return текст.slice(начало, текст.indexOf('>', м.index) + 1);
  }
  return '';
}

/** Элемент разметки с заданным id (целиком, с содержимым); пусто, если такого нет. */
function элементПоId(текст, id) {
  const м = new RegExp('<[a-z0-9]+[^>]*\\sid="' + id + '"').exec(текст);
  return м ? элементС(текст, м.index) : '';
}

/** Открывающий тег (только '<…>') первого узла, подходящего под шаблон; пусто, если нет. */
function открывающийТег(текст, шаблон) {
  const м = шаблон.exec(текст);
  return м ? текст.slice(м.index, текст.indexOf('>', м.index) + 1) : '';
}

/** Есть ли у открывающего тега класс (целым словом: граница слова в regex кириллицу не знает). */
function естьКласс(тег, класс) {
  const к = /\sclass="([^"]*)"/.exec(тег);
  return !!к && к[1].split(/\s+/).includes(класс);
}

/** Ширина, высота и прозрачность webp из заголовка файла (три вида: VP8, VP8L, VP8X); null — не webp. */
function размерWebp(буфер) {
  if (буфер.length < 30 || буфер.toString('latin1', 0, 4) !== 'RIFF' || буфер.toString('latin1', 8, 12) !== 'WEBP') return null;
  const вид = буфер.toString('latin1', 12, 16);
  if (вид === 'VP8X') {
    return {
      ширина: буфер.readUIntLE(24, 3) + 1, высота: буфер.readUIntLE(27, 3) + 1,
      прозрачность: (буфер[20] & 0x10) !== 0 || буфер.includes('ALPH')
    };
  }
  if (вид === 'VP8L') {
    const биты = буфер.readUInt32LE(21);
    return { ширина: (биты & 0x3fff) + 1, высота: ((биты >> 14) & 0x3fff) + 1, прозрачность: ((биты >> 28) & 1) === 1 };
  }
  if (вид === 'VP8 ') {
    return { ширина: буфер.readUInt16LE(26) & 0x3fff, высота: буфер.readUInt16LE(28) & 0x3fff, прозрачность: false };
  }
  return null;
}

/** Все id, которые ищет код игры (getElementById и $('…') в js/захват-*.js), и те, что код создаёт сам. */
function idКода() {
  const папка = path.join(КОРЕНЬ, 'js');
  const файлы = require('./пути-проекта.js').всеJsВПапке(папка).filter(ф => /\.js$/.test(ф));
  const ищут = new Set();
  const создаёт = new Set();
  файлы.forEach(ф => {
    const т = fs.readFileSync(require('./пути-проекта.js').вПапке(папка, ф), 'utf8');
    if (/^захват-/.test(ф)) {
      for (const м of т.matchAll(/(?:getElementById|\$)\(\s*'([^']+)'\s*\)/g)) ищут.add(м[1]);
    }
    // узлы, которые код делает сам (в любом файле: окно знаков и плашку выхода делают общие модули)
    for (const м of т.matchAll(/(?:\.id\s*=|\bID_[А-ЯЁA-Z_]+\s*=)\s*'([^']+)'/g)) создаёт.add(м[1]);
    for (const м of т.matchAll(/новаяКнопка\(\s*'([^']+)'/g)) создаёт.add(м[1]);
  });
  return { ищут, создаёт };
}

