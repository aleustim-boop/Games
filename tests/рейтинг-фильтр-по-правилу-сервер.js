/* --------- Сама проверка --------- */

async function проверитьВсё() {
  console.log('1. Запрашиваем рейтинг через HTTP');
  const ответ = await спросить('/рейтинг', {
    initData: подписьИгрока(ИГРОК_1001, 'Игрок1001'),
    игра: 'дурак'
  });

  проверить(ответ.код === 200, 'статус код 200');
  проверить(ответ.тело.ок === true, 'ответ содержит ок: true');
  проверить(ответ.тело.узналиВас === true, 'ответ содержит узналиВас: true');

  console.log('2. Проверяем наличие поля поПравилу');
  проверить(typeof ответ.тело.поПравилу === 'object' && ответ.тело.поПравилу !== null,
    'поле поПравилу существует и это объект');

  if (typeof ответ.тело.поПравилу === 'object' && ответ.тело.поПравилу !== null) {
    console.log('3. Проверяем наличие подкидной и переводной половин');
    проверить(typeof ответ.тело.поПравилу.подкидной === 'object' && ответ.тело.поПравилу.подкидной !== null,
      'поПравилу.подкидной существует и это объект');
    проверить(typeof ответ.тело.поПравилу.переводной === 'object' && ответ.тело.поПравилу.переводной !== null,
      'поПравилу.переводной существует и это объект');

    const подкидной = ответ.тело.поПравилу.подкидной;
    const переводной = ответ.тело.поПравилу.переводной;

    console.log('4. Проверяем структуру каждой половины');
    if (подкидной) {
      проверить(typeof подкидной.всего === 'number', 'подкидной.всего — число');
      проверить(typeof подкидной.яВТаблице === 'boolean', 'подкидной.яВТаблице — булево');
      проверить(подкидной.верхушка && Array.isArray(подкидной.верхушка), 'подкидной.верхушка — массив');
      проверить(подкидной.вокругМеня && Array.isArray(подкидной.вокругМеня), 'подкидной.вокругМеня — массив');
      if (подкидной.яВТаблице) {
        проверить(typeof подкидной.я === 'object' && подкидной.я !== null, 'подкидной.я — объект, когда яВТаблице true');
      }
    }

    if (переводной) {
      проверить(typeof переводной.всего === 'number', 'переводной.всего — число');
      проверить(typeof переводной.яВТаблице === 'boolean', 'переводной.яВТаблице — булево');
      проверить(переводной.верхушка && Array.isArray(переводной.верхушка), 'переводной.верхушка — массив');
      проверить(переводной.вокругМеня && Array.isArray(переводной.вокругМеня), 'переводной.вокругМеня — массив');
      if (переводной.яВТаблице) {
        проверить(typeof переводной.я === 'object' && переводной.я !== null, 'переводной.я — объект, когда яВТаблице true');
      }
    }

    console.log('5. Проверяем, что очки РАЗНЫЕ по правилам');
    const подкидойОчки = подкидной && подкидной.я ? подкидной.я.очки : null;
    const переводнойОчки = переводной && переводной.я ? переводной.я.очки : null;
    const общиеОчки = ответ.тело.я ? ответ.тело.я.очки : null;

    console.log('     Общие очки: ' + общиеОчки);
    console.log('     Подкидной: ' + подкидойОчки);
    console.log('     Переводной: ' + переводнойОчки);

    проверить(typeof подкидойОчки === 'number' && подкидойОчки > 0,
      'подкидной.я.очки — положительное число (было: ' + подкидойОчки + ')');
    проверить(typeof переводнойОчки === 'number' && переводнойОчки === 0,
      'переводной.я.очки — ноль (было: ' + переводнойОчки + ')');
    проверить(подкидойОчки !== переводнойОчки,
      'подкидной и переводной имеют РАЗНЫЕ очки (' + подкидойОчки + ' vs ' + переводнойОчки + ')');
    проверить(общиеОчки === подкидойОчки,
      'общие очки равны сумме подкидного (основное правило в дураке)');
  }
}

