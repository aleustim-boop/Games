/* =====================================================================
   РЕЙТИНГ: фильтр по правилу партии (подкидной / переводной).

   Что проверяем. Маршрут /рейтинг сервера возвращает поле `поПравилу`
   с двумя половинами счёта — отдельно для подкидной и переводной. Каждая
   половина содержит те же структуры (верхушка, вокругМеня, я), но считанные
   по своей половине очков. Партии без указанного правила (легаси или игра
   с ботом в браузере) идут только в общий счёт.

   Что значит «ломающий запуск». Временно в server/сервер.js меняем
   вызов рейтинга.срезСоВсемиПравилами на рейтинг.срезДляИгрока без
   второго аргумента. Это убирает поле поПравилу из ответа, и тесту
   нечего проверять — он краснеет.

   Запуск:
       node tests/рейтинг-фильтр-по-правилу-сервер.js
       node tests/рейтинг-фильтр-по-правилу-сервер.js 8798

   Ломающий запуск (обязан покраснеть):
       node tests/рейтинг-фильтр-по-правилу-сервер.js --сломать

   Выход 0 — провалов нет, 1 — есть.
   ===================================================================== */

