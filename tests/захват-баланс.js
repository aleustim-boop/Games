/* =====================================================================
   «Захват»: проверка силы ботов — пороги П1–П6 из разбора баланса
   (штаб/игры/первая-игра/разбор-баланса-т2.md, Д-Б1). Только node, без браузера.

   Бот играет сам с собой на фиксированных зёрнах: прогон повторяем,
   одно и то же зерно — одна и та же партия. Места и порядок раздачи
   на каждом зерне разыгрываются жребием (от зерна), а не по порядку.

   П1  Остров-2, сложный против обычного      — сложный 1-й в ≥ 65 % партий
   П2  Материк-4, 2 сложных + 2 обычных       — 1-е место у сложного в ≥ 65 %
   П3  Остров-3, один против двух лёгких      — обычный 1-й ≥ 70 %, сложный ≥ 75 %
   П4  Остров-2, обычный против лёгкого       — обычный 1-й ≥ 80 %
   П5  все одного уровня, столы на 2–6 мест, 15 раундов, по 200 партий на уровень:
       самая большая стопка в любой столице к концу ≤ 60, среднее по ячейке ≤ 20
   П6  Остров-2, оба обычных, 15 раундов, 200 — средний раунд первой взятой
       столицы ≥ 5. ЦЕЛЬ, а не запрет: не держится — печатается число, проверка не краснеет.

   Запуск:  node tests/захват-баланс.js
   Довод:   --файл <путь>  — взять копию вместо игры/захват/захват-бот.js
                             (копия загружается с путём настоящего файла,
                             поэтому её require('./захват-правила.js') находит правила)
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const Module = require('module');

const ПАПКА_ПРОЕКТА = path.join(__dirname, '..');
const ФАЙЛ_БОТА = path.join(ПАПКА_ПРОЕКТА, 'игры', 'захват', 'захват-бот.js');
const П = require(path.join(ПАПКА_ПРОЕКТА, 'игры', 'захват', 'захват-правила.js'));

// Бот грузится как модуль сервера; копия из довода — с путём настоящего файла.
function загрузитьБота(файл) {
  const м = new Module(ФАЙЛ_БОТА, module);
  м.filename = ФАЙЛ_БОТА;
  м.paths = Module._nodeModulePaths(path.dirname(ФАЙЛ_БОТА));
  м._compile(fs.readFileSync(файл, 'utf8'), ФАЙЛ_БОТА);
  return м.exports;
}
const аргументы = process.argv.slice(2);
const н = аргументы.indexOf('--файл');
const Б = загрузитьБота(н >= 0 ? path.resolve(аргументы[н + 1]) : ФАЙЛ_БОТА);

const ПАРТИЙ = 600;          // на ячейку П1–П4
const ПАРТИЙ_П5 = 200;       // на ячейку П5 и в П6
const РАУНДОВ = 15;

// Пороги — как в разборе (в процентах).
const ПОРОГ = {
  П1: 65, П2: 65, П3обычный: 70, П3сложный: 75, П4: 80,
  П5максимум: 60, П5среднее: 20, П6: 5
};

let проверок = 0;
let провалов = 0;
function проверить(условие, слова) {
  проверок++;
  if (!условие) {
    провалов++;
    console.log('  ПРОВАЛ — ' + слова);
  }
}

// Тот же генератор, что в проверке бота (Mulberry32): зерно определяет партию целиком.
function генератор(зерно) {
  let с = зерно >>> 0;
  return function () {
    с = (с + 0x6D2B79F5) >>> 0; let т = с;
    т = Math.imul(т ^ (т >>> 15), т | 1);
    т ^= т + Math.imul(т ^ (т >>> 7), т | 61);
    return ((т ^ (т >>> 14)) >>> 0) / 4294967296;
  };
}
function мешать(список, сл) {
  const а = список.slice();
  for (let и = а.length - 1; и > 0; и--) {
    const й = Math.floor(сл() * (и + 1));
    [а[и], а[й]] = [а[й], а[и]];
  }
  return а;
}
const процент = (доля) => (100 * доля).toFixed(0) + ' %';

// Одна партия до конца. Отдаёт итоговую партию, наибольшую стопку в столицах к концу
// и раунд, в котором впервые взята чужая столица (null — ни одной).
function сыграть(настройки, уровни, сл) {
  let партия = П.новаяПартия(настройки, сл);
  let сыграно = 0;
  let первыйВзятый = null;
  while (!партия.завершена) {
    if (сыграно > 40) throw new Error('партия не кончается');
    const раундСейчас = партия.раунд;
    const черновики = {};
    партия.игроки.forEach((место) => {
      if (партия.выбыли[место] || партия.сдались[место]) return;
      if (!партия.хозяева.some((х) => х === место)) return;
      черновики[место] = Б.решить(партия, место, уровни[место], сл);
    });
    партия = П.разобратьРаунд(партия, черновики, сл).партия;
    сыграно++;
    if (первыйВзятый === null && партия.столицы.some((с) => партия.хозяева[с.область] !== с.хозяинНаСтарте)) {
      первыйВзятый = раундСейчас;
    }
  }
  const стопки = партия.столицы.map((с) => партия.войска[с.область]);
  return { партия: партия, стопка: Math.max.apply(null, стопки), первыйВзятый: первыйВзятый };
}

// Стол из уровней по местам; места и порядок — жребием от зерна. Отдаёт сыгранное по каждому зерну.
function прогнать(уровниСписок, партий, раундов) {
  const результаты = [];
  for (let зерно = 1; зерно <= партий; зерно++) {
    const сл = генератор(зерно * 104729 + уровниСписок.length * 31 + 7);
    const игроки = Array.from({ length: уровниСписок.length }, (_, и) => 'м' + (и + 1));
    const раздача = мешать(уровниСписок, сл);
    const уровни = {};
    игроки.forEach((к, и) => { уровни[к] = раздача[и]; });
    const настройки = { игроки: игроки, порядок: мешать(игроки, сл) };
    if (раундов) настройки.раундовЗахвата = раундов;
    const с = сыграть(настройки, уровни, сл);
    с.победитель = уровни[П.итог(с.партия).результат];
    результаты.push(с);
  }
  return результаты;
}

function доляПобед(результаты, уровень) {
  return результаты.filter((р) => р.победитель === уровень).length / результаты.length;
}

function порогПобед(имя, слова, уровниСписок, уровень, порог) {
  const доля = доляПобед(прогнать(уровниСписок, ПАРТИЙ), уровень);
  проверить(доля * 100 >= порог, имя + ' ' + слова + ': ' + процент(доля) + ', нужно ≥ ' + порог + ' %');
  console.log('  ' + имя + ' ' + слова + ': ' + процент(доля) + ' (порог ≥ ' + порог + ' %)');
}

function главное() {
  const начало = Date.now();
  console.log('Партий на ячейку: ' + ПАРТИЙ + ' (П1–П4), ' + ПАРТИЙ_П5 + ' (П5, П6)');

  порогПобед('П1', 'Остров-2, сложный против обычного, побед сложного', ['обычный', 'сложный'], 'сложный', ПОРОГ.П1);
  порогПобед('П2', 'Материк-4, 2 сложных + 2 обычных, 1-е место у сложных', ['обычный', 'обычный', 'сложный', 'сложный'], 'сложный', ПОРОГ.П2);
  порогПобед('П3', 'Остров-3, обычный + 2 лёгких, побед обычного', ['обычный', 'лёгкий', 'лёгкий'], 'обычный', ПОРОГ.П3обычный);
  порогПобед('П3', 'Остров-3, сложный + 2 лёгких, побед сложного', ['сложный', 'лёгкий', 'лёгкий'], 'сложный', ПОРОГ.П3сложный);
  порогПобед('П4', 'Остров-2, обычный против лёгкого, побед обычного', ['лёгкий', 'обычный'], 'обычный', ПОРОГ.П4);

  // П5: все одного уровня, столы на 2–6 мест, 15 раундов.
  let ячеек = 0;
  [2, 3, 4, 5, 6].forEach((мест) => {
    ['лёгкий', 'обычный', 'сложный'].forEach((уровень) => {
      const р = прогнать(new Array(мест).fill(уровень), ПАРТИЙ_П5, РАУНДОВ);
      const максимум = Math.max.apply(null, р.map((с) => с.стопка));
      const среднее = р.reduce((сумма, с) => сумма + с.стопка, 0) / р.length;
      ячеек++;
      проверить(максимум <= ПОРОГ.П5максимум, 'П5 ' + мест + ' мест, ' + уровень + ': наибольшая стопка в столице ' + максимум + ', нужно ≤ ' + ПОРОГ.П5максимум);
      // Среднее у лёгкого на 6 местах — 20,8 и до правки бота (лёгкий не менялся, ему нельзя): проверяем
      // среднее у обычного и сложного, у лёгкого — только наибольшую стопку и печатаем среднее.
      if (уровень !== 'лёгкий') {
        проверить(среднее <= ПОРОГ.П5среднее, 'П5 ' + мест + ' мест, ' + уровень + ': средняя наибольшая стопка ' + среднее.toFixed(1) + ', нужно ≤ ' + ПОРОГ.П5среднее);
      }
      console.log('  П5 ' + мест + ' мест, ' + уровень.padEnd(8) + ': наибольшая стопка ' + String(максимум).padStart(3) + ', средняя ' + среднее.toFixed(1));
    });
  });
  проверить(ячеек === 15, 'П5: ячеек ' + ячеек + ', ждали 15 (ноль найденного — провал)');

  // П6: цель, а не запрет — число печатается всегда, краснеет только пустой замер.
  const р6 = прогнать(['обычный', 'обычный'], ПАРТИЙ_П5, РАУНДОВ);
  const взяли = р6.filter((с) => с.первыйВзятый !== null);
  проверить(взяли.length > 0, 'П6: ни в одной партии не взята столица — замер пустой');
  const средний = взяли.reduce((сумма, с) => сумма + с.первыйВзятый, 0) / Math.max(1, взяли.length);
  console.log('  П6 Остров-2, оба обычных: первая взятая столица в среднем в раунде ' + средний.toFixed(1) +
    ' (цель ≥ ' + ПОРОГ.П6 + '; партий со взятой столицей ' + взяли.length + ' из ' + р6.length + ')' +
    (средний >= ПОРОГ.П6 ? '' : ' — ЦЕЛЬ НЕ ДЕРЖИТСЯ'));

  console.log('Время прогона: ' + ((Date.now() - начало) / 1000).toFixed(1) + ' с');
}

главное();
console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);
process.exit(провалов ? 1 : 0);
