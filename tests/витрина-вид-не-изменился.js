/* =====================================================================
   ВИД ВИТРИНЫ НЕ ИЗМЕНИЛСЯ — доказательство для чистки мёртвого CSS.

   Зачем. Витрину (index.html) переделали: её настоящий вид теперь рисуют
   style-витрина.css и style-коллекция.css. В style.css остались старые
   правила «.плитка-игры[data-игра="…"]» (фон, order, aspect-ratio,
   border-radius, а также их варианты для «скоро»/:disabled и позиция
   пометки деберца) — их специфичность (класс+атрибут, 0-2-0 или 0-3-0)
   НИЖЕ, чем у «#экран-витрины .плитка-игры» (id+класс, 1-1-0) в
   style-витрина.css, а та задаёт «background: #141c1e» сокращённой
   записью — она обнуляет background-image независимо от состояния
   элемента. Значит часть старых правил physически не может ничего
   нарисовать. Здесь это не берётся на веру, а проверяется: эталон
   вычисленных стилей («getComputedStyle») снимается ДО правки, и после
   правки сравнивается с ним — 0 отличий доказывает, что убранное правило
   ни на что не влияло. Отличие есть — правило возвращается, оно живое.

   ЧТО СНИМАЕТСЯ на каждой из ширин 320, 390, 768, 1280: для каждой
   «.плитка-игры» внутри «#экран-витрины» и для каждого её потомка —
   вычисленный стиль набора «значимых» свойств (background*, color,
   opacity, filter, border*, box-shadow, width, height, display,
   cursor, order, aspect-ratio, позиция), и то же самое для псевдо-
   элементов «::before»/«::after» (плюс их «content»).

   Абсолютный адрес картинок («url("http://127.0.0.1:PORT/img/…")»)
   меняется от запуска к запуску вместе со свободным портом сервера —
   это не имеет отношения к делу, поэтому такой адрес перед сохранением
   ЧИСТИТСЯ (убирается «http://127.0.0.1:PORT», остаётся только путь):
   иначе эталон был бы «красным» на пустом месте при каждом прогоне.

   РЕЖИМЫ:
     --записать=путь.json   снять снимок и СОХРАНИТЬ его как эталон
                             (сравнение не делается, выход всегда 0);
     --эталон=путь.json     снять снимок и СРАВНИТЬ с эталоном из файла
                             (обычный режим проверки, красный на любом
                             отличии, выход 1 при хоть одном отличии);
     --корень=папка         открыть не сам проект, а копию по этому пути
                             (для ломающего запуска — портится КОПИЯ, не
                             настоящий файл проекта).
   Один из «--записать=»/«--эталон=» обязателен.

   ЛОМАЮЩИЙ ЗАПУСК (пример, руками, не флагом этого файла):
     1) скопировать проект во временную папку;
     2) в КОПИИ испортить одно живое свойство плитки, например
        в style-витрина.css поменять «background: #141c1e;» на другой
        цвет — это одно из свойств, которые реально рисуют витрину;
     3) node tests/витрина-вид-не-изменился.js --корень=<копия> --эталон=<путь к эталону>
     4) прогон обязан ПОКРАСНЕТЬ (испорченный цвет не совпадёт с эталоном).
     Настоящие файлы проекта при этом не трогаются ни секунды.

   Перед каждым запуском: node штаб/браузер-занят.js --ждать
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const http = require('http');
const { chromium, подготовитьПодделку } = require('./браузер-робот.js');

const АДРЕС_ХОЗЯИНА = '127.0.0.1';
// 8790/8791 — боевой сервер комнат и его дублёр, 8080 — постоянный стенд,
// 8765 — чужой дашборд на этой машине (см. штаб/уроки, «Порт 8765 занят»).
const ЗАПРЕЩЁННЫЕ_ПОРТЫ = [8790, 8791, 8080, 8765];

const ШИРИНЫ = [
  { ширина: 320, высота: 844 },
  { ширина: 390, высота: 844 },
  { ширина: 768, высота: 1024 },
  { ширина: 1280, высота: 900 }
];

// Свойства, которые считаем «значимыми» для внешнего вида плитки —
// список из задания («background*, color, opacity, filter, border*,
// box-shadow, width, height, display») плюс то, что напрямую относится
// к вырезаемым правилам (order, aspect-ratio, позиция пометки, cursor) —
// лишним не мешает, только строже проверка.
const СВОЙСТВА = [
  'display', 'width', 'height', 'color', 'opacity', 'filter', 'boxShadow', 'cursor',
  'borderTopWidth', 'borderRightWidth', 'borderBottomWidth', 'borderLeftWidth',
  'borderTopColor', 'borderRightColor', 'borderBottomColor', 'borderLeftColor',
  'borderTopStyle', 'borderRightStyle', 'borderBottomStyle', 'borderLeftStyle',
  'borderTopLeftRadius', 'borderTopRightRadius', 'borderBottomRightRadius', 'borderBottomLeftRadius',
  'backgroundColor', 'backgroundImage', 'backgroundPosition', 'backgroundSize',
  'backgroundRepeat', 'backgroundAttachment', 'backgroundClip', 'backgroundOrigin', 'backgroundBlendMode',
  'order', 'aspectRatio', 'gridColumnStart', 'gridColumnEnd',
  'position', 'top', 'right', 'bottom', 'left', 'zIndex'
];
// У псевдоэлементов дополнительно важен «content» — по нему живёт стрелка «↗».
const СВОЙСТВА_ПСЕВДО = СВОЙСТВА.concat(['content']);

function разобратьАргументы() {
  const итог = { записать: null, эталон: null, корень: null };
  for (const строка of process.argv.slice(2)) {
    const дал = (имя) => строка.indexOf('--' + имя + '=') === 0 ? строка.slice(имя.length + 3) : null;
    итог.записать = итог.записать || дал('записать');
    итог.эталон = итог.эталон || дал('эталон');
    итог.корень = итог.корень || дал('корень');
  }
  return итог;
}

/* ---------------------------------------------------------------------
   Свой временный статический сервер — раздаёт папку КОРЕНЬ как есть.
   --------------------------------------------------------------------- */

const ТИПЫ_ФАЙЛОВ = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.woff2': 'font/woff2'
};

function запрещённыйАдрес(адрес) {
  const низ = адрес.toLowerCase();
  if (низ.indexOf('.env') !== -1) return true;
  const части = низ.split(/[\\/]/).filter(Boolean);
  if (части.length && части[0] === 'bot') return true;
  return части.some((часть) => часть.charAt(0) === '.');
}

function поднятьСервер(корень, порт) {
  return new Promise((готово) => {
    const сервер = http.createServer((запрос, ответ) => {
      let адрес;
      try { адрес = decodeURIComponent(запрос.url.split('?')[0]); }
      catch (ошибка) { ответ.writeHead(400); ответ.end('непонятный адрес'); return; }
      if (адрес === '/') адрес = '/index.html';
      if (запрещённыйАдрес(адрес)) { ответ.writeHead(403); ответ.end('доступ закрыт'); return; }
      const относительный = адрес.replace(/^\/+/, '');
      const файл = path.join(корень, относительный);
      if (файл !== корень && !файл.startsWith(корень + path.sep)) {
        ответ.writeHead(403); ответ.end('доступ закрыт: файл вне корня'); return;
      }
      fs.readFile(файл, (ошибка, данные) => {
        if (ошибка) { ответ.writeHead(404); ответ.end('не найдено: ' + адрес); return; }
        ответ.writeHead(200, {
          'Content-Type': ТИПЫ_ФАЙЛОВ[path.extname(файл).toLowerCase()] || 'application/octet-stream',
          'Cache-Control': 'no-store'
        });
        ответ.end(данные);
      });
    });
    сервер.listen(порт, АДРЕС_ХОЗЯИНА, () => готово(сервер));
  });
}

function свободныйПорт() {
  return new Promise((готово, брак) => {
    const проба = http.createServer();
    проба.on('error', брак);
    проба.listen(0, АДРЕС_ХОЗЯИНА, () => {
      const порт = проба.address().port;
      проба.close(() => готово(порт));
    });
  });
}

async function выбратьСвободныйПорт() {
  for (let попытка = 0; попытка < 8; попытка++) {
    const порт = await свободныйПорт();
    if (ЗАПРЕЩЁННЫЕ_ПОРТЫ.indexOf(порт) === -1) return порт;
  }
  throw new Error('не удалось получить свободный порт мимо запрещённых');
}

/* ---------------------------------------------------------------------
   Снятие вычисленного стиля со страницы.
   --------------------------------------------------------------------- */

async function снятьШирину(браузер, адрес, ширина, высота) {
  const контекст = await браузер.newContext({ viewport: { width: ширина, height: высота } });
  const страница = await контекст.newPage();
  await подготовитьПодделку(страница, { версия: '8.0' });
  await страница.goto(адрес + '/index.html');
  await страница.waitForSelector('#экран-витрины.экран--виден', { timeout: 8000 }).catch(() => null);
  await страница.evaluate(() => (document.fonts && document.fonts.ready) || Promise.resolve());
  await страница.evaluate(() => new Promise((г) => requestAnimationFrame(() => requestAnimationFrame(г))));
  await страница.waitForTimeout(200);

  const снимок = await страница.evaluate((своиства) => {
    const своиства_ = своиства.база;
    const своиства_псевдо = своиства.псевдо;
    function снятьСвойства(объектСтиля, список) {
      const итог = {};
      for (const имя of список) { итог[имя] = String(объектСтиля[имя]); }
      return итог;
    }
    function снятьЭлемент(эл) {
      const стиль = getComputedStyle(эл);
      const до = getComputedStyle(эл, '::before');
      const после = getComputedStyle(эл, '::after');
      return {
        тег: эл.tagName.toLowerCase(),
        класс: эл.className || '',
        стиль: снятьСвойства(стиль, своиства_),
        before: снятьСвойства(до, своиства_псевдо),
        after: снятьСвойства(после, своиства_псевдо)
      };
    }
    const плитки = Array.prototype.slice.call(document.querySelectorAll('#экран-витрины .плитка-игры'));
    return плитки.map((плитка) => {
      const базовое = снятьЭлемент(плитка);
      базовое.игра = плитка.getAttribute('data-игра') || '';
      базовое.потомки = Array.prototype.slice.call(плитка.querySelectorAll('*')).map(снятьЭлемент);
      return базовое;
    });
  }, { база: СВОЙСТВА, псевдо: СВОЙСТВА_ПСЕВДО });

  await контекст.close();
  return снимок;
}

/* ---------------------------------------------------------------------
   Порт/хозяин в значениях («url("http://127.0.0.1:54321/img/…")») —
   лишний шум: разные свободные порты в разных запусках. Чистим.
   --------------------------------------------------------------------- */

const ШАБЛОН_ХОЗЯИНА = /https?:\/\/127\.0\.0\.1:\d+/g;

function зачиститьХозяина(значение) {
  return typeof значение === 'string' ? значение.replace(ШАБЛОН_ХОЗЯИНА, '') : значение;
}

function зачиститьСнимок(поШиринам) {
  const обойти = (узел) => {
    if (Array.isArray(узел)) return узел.map(обойти);
    if (узел && typeof узел === 'object') {
      const итог = {};
      for (const ключ of Object.keys(узел)) итог[ключ] = обойти(узел[ключ]);
      return итог;
    }
    return зачиститьХозяина(узел);
  };
  return обойти(поШиринам);
}

/* ---------------------------------------------------------------------
   Сравнение снимка с эталоном.
   --------------------------------------------------------------------- */

let проверок = 0;
let провалов = 0;

function проверить(метка, условие, что, детали) {
  проверок++;
  if (условие) { console.log('  ок    — ' + метка + ': ' + что); return true; }
  провалов++;
  console.log('  ПЛОХО — ' + метка + ': ' + что + (детали ? ' (' + детали + ')' : ''));
  return false;
}

function сравнитьСтили(метка, путь, a, b) {
  if (!a || !b) { проверить(метка, false, 'есть оба стиля для ' + путь, 'один из них отсутствует'); return; }
  const ключи = Object.keys(a);
  for (const ключ of ключи) {
    проверить(метка, a[ключ] === b[ключ], путь + ' → ' + ключ + ' не изменилось',
      a[ключ] === b[ключ] ? undefined : ('эталон «' + a[ключ] + '», сейчас «' + b[ключ] + '»'));
  }
}

function сравнитьЭлемент(метка, путь, э1, э2) {
  if (!проверить(метка, Boolean(э1) && Boolean(э2), путь + ' — элемент найден в обоих снимках',
      !э1 ? 'нет в эталоне' : 'нет в новом снимке')) return;
  проверить(метка, э1.тег === э2.тег && э1.класс === э2.класс, путь + ' — тот же тег и класс',
    (э1.тег === э2.тег && э1.класс === э2.класс) ? undefined : ('было «' + э1.тег + '.' + э1.класс + '», стало «' + э2.тег + '.' + э2.класс + '»'));
  сравнитьСтили(метка, путь, э1.стиль, э2.стиль);
  сравнитьСтили(метка, путь + '::before', э1.before, э2.before);
  сравнитьСтили(метка, путь + '::after', э1.after, э2.after);
}

function сравнитьШирину(ширина, эталонПлитки, новыеПлитки) {
  const метка = 'ширина ' + ширина;
  проверить(метка, эталонПлитки.length === новыеПлитки.length,
    'число плиток совпадает с эталоном (' + эталонПлитки.length + ')',
    эталонПлитки.length === новыеПлитки.length ? undefined : ('сейчас плиток ' + новыеПлитки.length));
  const по_игре_2 = {};
  новыеПлитки.forEach((п) => { по_игре_2[п.игра || '?'] = п; });
  эталонПлитки.forEach((э, индекс) => {
    const ключ = э.игра || ('#' + индекс);
    const текущая = по_игре_2[э.игра] || новыеПлитки[индекс];
    сравнитьЭлемент(метка, 'плитка «' + ключ + '»', э, текущая);
    if (текущая) {
      проверить(метка, э.потомки.length === текущая.потомки.length,
        'плитка «' + ключ + '»: число потомков совпадает (' + э.потомки.length + ')',
        э.потомки.length === текущая.потомки.length ? undefined : ('сейчас потомков ' + (текущая.потомки ? текущая.потомки.length : 0)));
      э.потомки.forEach((потомок, i) => {
        сравнитьЭлемент(метка, 'плитка «' + ключ + '» → потомок #' + i + ' (' + потомок.тег + '.' + потомок.класс + ')',
          потомок, текущая.потомки && текущая.потомки[i]);
      });
    }
  });
}

(async () => {
  const аргументы = разобратьАргументы();
  if (!аргументы.записать && !аргументы.эталон) {
    console.error('нужен один из доводов: --записать=путь.json или --эталон=путь.json');
    process.exit(2);
  }

  const КОРЕНЬ = аргументы.корень ? path.resolve(аргументы.корень) : path.join(__dirname, '..');
  if (!fs.existsSync(path.join(КОРЕНЬ, 'index.html'))) {
    console.error('в корне «' + КОРЕНЬ + '» нет index.html — неверный путь?');
    process.exit(2);
  }

  console.log(аргументы.записать
    ? '=== Снимаю эталон вида витрины: ' + КОРЕНЬ + ' ==='
    : '=== Сравниваю вид витрины с эталоном: ' + КОРЕНЬ + ' ===');

  const порт = await выбратьСвободныйПорт();
  const сервер = await поднятьСервер(КОРЕНЬ, порт);
  const адрес = 'http://' + АДРЕС_ХОЗЯИНА + ':' + порт;
  const браузер = await chromium.launch();

  let поШиринам = {};
  try {
    for (const { ширина, высота } of ШИРИНЫ) {
      const плитки = await снятьШирину(браузер, адрес, ширина, высота);
      поШиринам[String(ширина)] = { плитки };
      if (!аргументы.записать) {
        проверить('ширина ' + ширина, плитки.length > 0, 'на странице нашлись плитки (' + плитки.length + ')',
          плитки.length === 0 ? 'селектор «#экран-витрины .плитка-игры» не нашёл ни одной' : undefined);
      }
    }
  } finally {
    await браузер.close();
    await new Promise((г) => сервер.close(г));
  }

  поШиринам = зачиститьСнимок(поШиринам);

  if (аргументы.записать) {
    const путь = path.resolve(аргументы.записать);
    fs.mkdirSync(path.dirname(путь), { recursive: true });
    fs.writeFileSync(путь, JSON.stringify({ версия: 1, ширины: поШиринам }, null, 2), 'utf8');
    console.log('Эталон записан: ' + путь);
    process.exitCode = 0;
    return;
  }

  const путьЭталона = path.resolve(аргументы.эталон);
  if (!fs.existsSync(путьЭталона)) {
    console.error('эталон не найден: ' + путьЭталона + ' — сначала запустите с --записать=');
    process.exit(2);
  }
  const эталон = JSON.parse(fs.readFileSync(путьЭталона, 'utf8'));

  for (const { ширина } of ШИРИНЫ) {
    const ключ = String(ширина);
    const эталонШирины = (эталон.ширины && эталон.ширины[ключ] && эталон.ширины[ключ].плитки) || [];
    const новыеШирины = (поШиринам[ключ] && поШиринам[ключ].плитки) || [];
    сравнитьШирину(ширина, эталонШирины, новыеШирины);
  }

  console.log('----------------------------------------');
  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
  process.exitCode = провалов ? 1 : 0;
})().catch((ошибка) => {
  console.error('оборвалось: ' + (ошибка && ошибка.stack ? ошибка.stack : ошибка));
  process.exit(1);
});
