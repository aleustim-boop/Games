/* Проверка двери /знакомые от начала до конца, на своём сервере (порт 8793).
   Настоящий сервер на 8790 при этом не трогается.

   Что делаем: двое «садятся» за стол с настоящими подписями Telegram,
   сервер раздаёт карты и заводит знакомство, потом каждый спрашивает
   свой список. Токен бота читается из bot/.env и НИКУДА не выводится. */

const path = require('path');
/* Живые файлы владельца (знакомства и статистика) лежат там же, куда пишет
   серверный код, а путь к ним зашит. Поэтому снимаем их копию до начала
   и возвращаем при любом исходе — см. tests/сберечь-данные.js. */
require('./сберечь-данные.js').сберечь();
const crypto = require('crypto');

const КОРЕНЬ = require('path').resolve(__dirname, '..');   // корень проекта — от этого файла, а не зашитый
const сервер = require(path.join(КОРЕНЬ, 'server/сервер.js'));
const знакомые = require(path.join(КОРЕНЬ, 'server/знакомые.js'));
/* Нужен ровно для одного: остановить сторожа комнат в конце проверки,
   иначе процесс не завершится сам и придётся выходить резко. */
const комнаты = require(path.join(КОРЕНЬ, 'server/комнаты.js'));

/* Порт можно назвать доводом: «node tests/проверка-знакомых.js 8823».
   Раньше он был вписан числом намертво, и когда на 8793 поселился дашборд
   штаба, проверка честно поговорила с ним и сорвалась на «дашборд то… —
   это не JSON». Беда была не в игре, а в занятом порте, но выглядела
   как поломка сервера. */
const ПОРТ = Number(process.argv[2]) || 8793;
const АДРЕС = 'http://127.0.0.1:' + ПОРТ;

const токен = (сервер.прочитатьНастройки().BOT_TOKEN || '').trim();
if (!токен) {
  console.log('НЕТ ТОКЕНА в bot/.env — проверить подпись нечем, проверка не пойдёт.');
  process.exit(2);
}
console.log('Токен бота найден (длина ' + токен.length + ' знаков, сам он никуда не выводится).');

/** Собрать настоящую initData: как её подписывает Telegram. */
function подписать(кто) {
  const поля = new URLSearchParams();
  поля.set('user', JSON.stringify(кто));
  поля.set('auth_date', String(Math.floor(Date.now() / 1000)));
  поля.set('query_id', 'проверка');
  const строки = [];
  for (const пара of поля) строки.push(пара[0] + '=' + пара[1]);
  строки.sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(токен).digest();
  const подпись = crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
  поля.set('hash', подпись);
  return поля.toString();
}

const аня = подписать({ id: 900001, first_name: 'Аня' });
const боря = подписать({ id: 900002, first_name: 'Боря' });

let стук = function (путь, тело) {
  return fetch(АДРЕС + путь, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(тело || {})
  }).then(function (ответ) {
    return ответ.json().then(function (данные) {
      return { номер: ответ.status, данные: данные };
    });
  });
};

/* Каждый ответ двери /знакомые пропускаем через общего сторожа:
   он смотрит, не появилось ли лишнее поле и нет ли номеров Telegram.
   Раньше эту дверь не осматривал никто. */
const сторож = require('./сторож-полей.js').создатьСторожа(function (условие, что) {
  if (!условие) { всёХорошо = false; console.log('  БЕДА ' + что); }
});
const стукБезСторожа = стук;
стук = function (путь, тело) {
  return стукБезСторожа(путь, тело).then(function (ответ) {
    if (путь === '/знакомые') сторож.осмотретьЗнакомых(ответ.данные, 'дверь /знакомые');
    return ответ;
  });
};

let всёХорошо = true;
function проверить(что, правда) {
  console.log((правда ? '  ок   ' : '  БЕДА ') + что);
  if (!правда) всёХорошо = false;
}

async function пройти() {
  const создание = await стук('/создать', { initData: аня, имя: 'Аня' });
  проверить('комната создана, код есть', создание.номер === 200 && Boolean(создание.данные.код));
  const код = создание.данные.код;
  const пропускАни = создание.данные.пропуск;

  const вход = await стук('/войти', { код: код, initData: боря, имя: 'Боря' });
  проверить('Боря вошёл', вход.номер === 200 && Boolean(вход.данные.пропуск));
  const пропускБори = вход.данные.пропуск;
  проверить('карты уже розданы (этап «игра»)',
    вход.данные.состояние && вход.данные.состояние.этап === 'игра');

  console.log('Знакомств в памяти сервера: ' + знакомые.сколькоЗнакомств());
  проверить('знакомство записано ровно одно', знакомые.сколькоЗнакомств() === 1);

  const уАни = await стук('/знакомые', { initData: аня });
  console.log('  ответ Ане: ' + JSON.stringify(уАни.данные));
  проверить('Аню узнали', уАни.данные.узналиВас === true);
  проверить('у Ани один знакомый — Боря',
    уАни.данные.знакомые.length === 1 && уАни.данные.знакомые[0].имя === 'Боря');
  проверить('и он сейчас за столом', уАни.данные.знакомые[0].сейчасИграет === true);
  проверить('номера Telegram в ответе нет',
    JSON.stringify(уАни.данные).indexOf('900002') === -1 &&
    /* Набор полей строки сверяем ЦЕЛИКОМ, а не по одному: так новое поле
       не проскочит молча. Поле «игра» добавил сервер — во что играли
       с этим человеком в последний раз («дурак» или «шашки»), слово
       из закрытого реестра. Номера Telegram в строке нет и быть не должно. */
    Object.keys(уАни.данные.знакомые[0]).join(',') === 'имя,сейчасИграет,игра');

  const уБори = await стук('/знакомые', { initData: боря });
  console.log('  ответ Боре: ' + JSON.stringify(уБори.данные));
  проверить('взаимность: Боря видит Аню',
    уБори.данные.знакомые.length === 1 && уБори.данные.знакомые[0].имя === 'Аня');

  const мусор = await стук('/знакомые', { initData: 'подпись=подделка&hash=00' });
  console.log('  ответ подделке: ' + JSON.stringify(мусор.данные));
  проверить('подделку не узнали и списка ей не дали',
    мусор.номер === 200 && мусор.данные.узналиВас === false &&
    мусор.данные.знакомые.length === 0);

  const пусто = await стук('/знакомые', {});
  проверить('запрос без подписи — тоже пустой список',
    пусто.номер === 200 && пусто.данные.узналиВас === false);

  // Оба встали из-за стола — «сейчас играет» обязано погаснуть.
  await стук('/выйти', { код: код, пропуск: пропускАни });
  await стук('/выйти', { код: код, пропуск: пропускБори });
  const послеВыхода = await стук('/знакомые', { initData: аня });
  console.log('  ответ Ане после выхода: ' + JSON.stringify(послеВыхода.данные));
  проверить('знакомый остался в списке', послеВыхода.данные.знакомые.length === 1);
  проверить('но за столом его больше нет',
    послеВыхода.данные.знакомые[0].сейчасИграет === false);
}

const живой = сервер.запустить(ПОРТ, 2000);

пройти().then(function () {
  console.log(всёХорошо ? 'ИТОГ: всё сошлось.' : 'ИТОГ: есть беды, смотри выше.');
}).catch(function (сбой) {
  всёХорошо = false;
  console.log('Проверка сорвалась: ' + сбой.message);
}).then(function () {
  // Убираем за собой: выдуманные знакомства в настоящем файле не нужны.
  знакомые.забытьВсё();
  знакомые.дописать();
  /* Выходим ПО-ХОРОШЕМУ, а не «process.exit» посреди работы.
     Раньше здесь стоял резкий выход, и на Windows он ронял процесс
     на месте («Assertion failed … uv async»): код выхода получался 127,
     и проверка выглядела красной сразу после честного «всё сошлось».
     Теперь гасим то, что держит процесс живым, — сторожа комнат
     и само гнездо, — и даём Node завершиться самому. */
  process.exitCode = всёХорошо ? 0 : 1;
  try { комнаты.остановитьУборку(); } catch (сбой) { /* уже остановлена */ }
  try { живой.close(); } catch (сбой) { /* уже закрыто */ }
});
