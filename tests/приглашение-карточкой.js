async function проверитьИгры() {
  console.log('1. Приглашение в конкретную игру');
  let прошло = 0;
  for (const ждём of ИГРЫ) {
    const игрок = новыйИгрок();
    const р = await пригласить({
      initData: подписьИгрока(игрок, 'Аня'), вид: 'приглашение', игра: ждём.игра,
      ссылка: ПОДЛОГ_ССЫЛКИ, текст: ПОДЛОГ_ТЕКСТА
    });
    const к = сверитьКарточку(р, ждём.картинка, ждёмХвост(игрок, ждём.метка), ждём.игра);
    if (!к) continue;
    const подпись = String(к.caption || '');
    проверить(подпись.indexOf('Аня зовёт') === 0, ждём.игра + ': подпись не начинается с имени из подписи: ' + подпись);
    проверить(подпись.toLowerCase().indexOf(ждём.слово) !== -1, ждём.игра + ': в подписи нет «' + ждём.слово + '»: ' + подпись);
    проверить(/заходи!$/.test(подпись), ждём.игра + ': подпись не кончается «заходи!»: ' + подпись);
    прошло++;
  }
  проверить(прошло === ИГРЫ.length, 'карточек игр проверено ' + прошло + ' из ' + ИГРЫ.length);
}

async function проверитьОбщее() {
  console.log('2. Общее приглашение: без игры и с неизвестной игрой');
  const случаи = [
    { где: 'без игры', тело: {} },
    { где: 'неизвестная игра', тело: { игра: 'взлом<b>' } },
    { где: 'игра не строкой', тело: { игра: ['шашки'] } }
  ];
  let прошло = 0;
  for (const случай of случаи) {
    const игрок = новыйИгрок();
    const тело = Object.assign({ initData: подписьИгрока(игрок, 'Боря'), вид: 'приглашение',
      ссылка: ПОДЛОГ_ССЫЛКИ, текст: ПОДЛОГ_ТЕКСТА }, случай.тело);
    const к = сверитьКарточку(await пригласить(тело), ОБЩАЯ, ждёмХвост(игрок, ''), случай.где);
    if (!к) continue;
    проверить(к.caption === 'Боря зовёт в настольные игры прямо в Telegram — заходи!',
      случай.где + ': подпись общего приглашения: ' + к.caption);
    проверить(String(к.caption).indexOf('взлом') === -1, случай.где + ': слово клиента попало в подпись');
    прошло++;
  }
  проверить(прошло === случаи.length, 'общих приглашений проверено ' + прошло + ' из ' + случаи.length);
}

