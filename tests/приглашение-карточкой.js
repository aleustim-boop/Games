const журнал = [];
let ботМолчит = false;
function поддельныйTelegram(метод, тело) {
  журнал.push({ метод: метод, тело: тело });
  if (метод === 'getMe') {
    return ботМолчит ? { ok: false, error_code: 401, description: 'Unauthorized' }
      : { ok: true, result: { id: 777, is_bot: true, username: ИМЯ_БОТА } };
  }
  if (метод === 'savePreparedInlineMessage') return { ok: true, result: { id: 'pm' + журнал.length } };
  if (метод === 'sendMessage') return { ok: true, result: { message_id: журнал.length } };
  return { ok: false, error_code: 400, description: 'Bad Request' };
}

function подписать(поля, токен) {
  const строки = Object.keys(поля).map(function (к) { return к + '=' + поля[к]; }).sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(токен).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}

function подписьИгрока(номер, имя, токен) {
  const поля = {
    query_id: 'AAF' + номер,
    user: JSON.stringify({ id: номер, first_name: имя, username: 'igrok' + номер }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  const всё = Object.assign({}, поля, { hash: подписать(поля, токен || ТОКЕН_ДЛЯ_ПРОБЫ) });
  return Object.keys(всё).map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(всё[к]); }).join('&');
}

let ПОРТ = 0;
function спросить(путь, тело) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: '127.0.0.1', port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (сбой) { разобрано = null; }
        готово({ код: ответ.statusCode, тело: разобрано || {} });
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

/** Позвать /приглашение и вернуть ответ и то, что ушло в savePreparedInlineMessage. */
async function пригласить(тело) {
  const до = журнал.length;
  const ответ = await спросить('/приглашение', тело);
  const ушло = журнал.slice(до).find(function (з) { return з.метод === 'savePreparedInlineMessage'; });
  return { ответ: ответ.тело, результат: ушло ? ушло.тело.result : null };
}

/* Каждому сценарию — свой игрок: пауза 3 с считается по номеру игрока. */
let следующийИгрок = 930000;
function новыйИгрок() { return ++следующийИгрок; }

/** Хвост ?start= у карточки: inv_<код этого игрока>[_<метка>] (код берём из того же учёта, что и сервер). */
function ждёмХвост(номер, метка) {
  return 'inv_' + привёлДруга.кодПригласившего(номер) + (метка ? '_' + метка : '');
}

/** Общие признаки фото-карточки: картинка, кнопка «Играть», никакой разметки. */
function сверитьКарточку(р, картинка, хвост, где) {
  проверить(р.ответ.ок === true, где + ': ответ не ok:true (' + JSON.stringify(р.ответ) + ')');
  проверить(!!р.результат, где + ': в Telegram не ушло подготовленное сообщение');
  if (!р.результат) return null;
  const к = р.результат;
  const ждёмКартинку = АДРЕС + encodeURI(картинка);
  проверить(к.type === 'photo', где + ': вид карточки «' + к.type + '», а ждали photo');
  проверить(к.photo_url === ждёмКартинку, где + ': photo_url «' + к.photo_url + '», ждали «' + ждёмКартинку + '»');
  проверить(к.thumbnail_url === ждёмКартинку, где + ': thumbnail_url не та же обложка');
  проверить(fs.existsSync(path.join(КОРЕНЬ, картинка)), где + ': файла обложки нет в проекте: ' + картинка);
  проверить(!('parse_mode' in к), где + ': стоит parse_mode — чужое имя читалось бы разметкой');
  const кнопка = к.reply_markup && к.reply_markup.inline_keyboard && к.reply_markup.inline_keyboard[0] &&
    к.reply_markup.inline_keyboard[0][0];
  проверить(!!кнопка && кнопка.text === 'Играть', где + ': кнопка не «Играть»');
  const ждёмСсылку = 'https://t.me/' + ИМЯ_БОТА + '?start=' + хвост;
  проверить(!!кнопка && кнопка.url === ждёмСсылку,
    где + ': кнопка ведёт на «' + (кнопка && кнопка.url) + '», ждали «' + ждёмСсылку + '»');
  проверить(хвост.length <= 64, где + ': хвост ?start= длиннее 64 знаков');
  const всё = JSON.stringify(к);
  проверить(всё.indexOf(ПОДЛОГ_ССЫЛКИ) === -1, где + ': присланная клиентом ссылка попала в карточку');
  проверить(всё.indexOf(ПОДЛОГ_ТЕКСТА) === -1, где + ': присланный клиентом текст попал в карточку');
  return к;
}

