/** Разбор [точки] и [поверх]. Ноль сравнённых точек — провал, а не пропуск. */
function разобратьТочки(п, м, т) {
  const поверх = м.поверх || [];
  const плохиеТочки = поверх.filter(function (з) { return !з.плашка; });
  проверить(поверх.length === 5 && плохиеТочки.length === 0,
    п + '[поверх] в пяти точках плашки первый узел — плашка или её потомок (точек ' + поверх.length + '; не плашка: ' +
    (плохиеТочки.map(function (з) { return з.x + ',' + з.y + ' ' + з.узел; }).join('; ') || 'нет') + ')');
  if (!проверить(т && т.всего > 0, п + '[точки] область плашки снята и сравнена (точек: ' + (т ? т.всего : 0) + ')')) return;
  проверить(т.отличий === 0,
    п + '[точки] плашка над страницей = плашка на пустой странице: отличается ' + т.отличий + ' из ' + т.всего + ' точек' +
    (т.первая ? ' (первая ' + т.первая + ', наибольшая разница канала ' + т.макс + ', рамка отличий ' + т.рамка + ')' : '') + ', область ' + т.область +
    '; справка: страница под плашкой отличается от пустого фона в ' + т.страницаПодПлашкой.отличий + ' точках');
}

function разобратьПлашку(св, п, м, размер, т) {
  if (!проверить(м.плашкаВидна, п + 'плашка голосования найдена и видна (узел ' + (м.плашкаЕсть ? 'есть' : 'не найден') + ')')) return;
  const пл = м.плашка;
  проверить(внутри(пл, { x: 0, y: 0, r: м.W, b: м.H }), п + '[в-экране] плашка целиком в экране (' + кратко(пл) + ', экран ' + м.W + '×' + м.H + ')');
  if (проверить(Boolean(м.колонка) && м.пределШирины > 0, п + '[колонка] колонка экрана и предел ширины листа найдены')) {
    проверить(пл.x >= м.колонка.x - 0.5 && пл.r <= м.колонка.r + 0.5 && пл.w <= м.пределШирины + 0.5,
      п + '[колонка] плашка в ширине колонки (' + Math.round(пл.x) + '–' + Math.round(пл.r) + ' при колонке ' + Math.round(м.колонка.x) + '–' + Math.round(м.колонка.r) + ', ширина ' + Math.round(пл.w) + ' ≤ ' + м.пределШирины + ')');
  }
  if (размер.w === 320) проверить(пл.h <= ПРЕДЕЛ_ВЫСОТЫ_320 + 0.5, п + '[высота] на 320 плашка не выше ' + ПРЕДЕЛ_ВЫСОТЫ_320 + ' (вышло ' + Math.round(пл.h) + ')');
  проверить(пл.b <= м.H * 2 / 3 + 0.5, п + '[низ] плашка не заходит в нижнюю треть (низ ' + Math.round(пл.b) + ', треть с ' + Math.round(м.H * 2 / 3) + ')');
  проверить(м.плашкаСверху, п + 'плашку ничто не перекрывает (в её середине: ' + м.вСерединеПлашки + ')');
  проверить(альфа(м.фон) === 1 && м.непрозрачность === '1',
    п + '[непрозрачна] фон плашки сплошной, страница сквозь неё не видна (фон ' + м.фон + ', opacity ' + м.непрозрачность + ')');
  проверить(м.видимыйФон === м.фонКарточки, п + '[как-карточка] фон плашки — как у карточки лобби (' + м.видимыйФон + ' / карточка ' + м.фонКарточки + ')');

  разобратьТочки(п, м, т);

  const нужны = [];
  if (св.плашка) нужны.push('строка');
  if (св.плашка && св.кнопки) нужны.push('за', 'против');
  if (св.плашка && !св.кнопки) нужны.push('подпись');
  if (св.отказ) нужны.push('причина');
  нужны.forEach(function (имя) {
    const з = м.части[имя];
    if (!проверить(з && з.виден, п + 'часть «' + имя + '» найдена и видна')) return;
    проверить(!з.обрезан, п + '[обрезка] текст «' + имя + '» не обрезан (scrollWidth / clientWidth: ' + з.ширины + ')');
    if (имя === 'за' || имя === 'против') проверить(внутри(з, пл), п + '[кнопки] кнопка «' + з.текст + '» целиком в плашке (' + кратко(з) + ', плашка ' + кратко(пл) + ')');
  });
  if (св.плашка) {
    проверить(м.части.текст.текст === (св.имя || 'Аня') + ' предлагает закончить партию', п + 'текст плашки целиком («' + м.части.текст.текст + '»)');
    const отсчётТекст = м.части.отсчёт.текст;
    if (св.секунд > 0) проверить(/^ещё \d+ сек\.$/.test(отсчётТекст), п + 'отсчёт идёт («' + отсчётТекст + '»)');
    else проверить(отсчётТекст === '' && !м.части.отсчёт.виден, п + 'на нуле слов отсчёта нет, плашка стоит («' + отсчётТекст + '»)');
    if (!св.кнопки) проверить(!м.части.за.виден && !м.части.против.виден, п + 'кнопок нет — вместо них подпись');
  }
  if (св.отказ) {
    проверить(м.части.причина.текст === св.отказ, п + 'причина — словами двери («' + м.части.причина.текст + '»)');
    const з = м.части.причина;
    проверить(з.виден && м.высотаКнопки > 0 && з.h >= м.высотаКнопки - 0.5,
      п + '[причина] причина не тонкая полоска: высота ' + Math.round(з.h || 0) + ' ≥ высоты кнопок голосования ' + м.высотаКнопки);
    проверить(альфа(м.причинаФон) > 0 && /^"/.test(м.причинаЗначок),
      п + '[причина] причина оформлена как тревога: своя заливка (' + м.причинаФон + ') и значок (content ' + м.причинаЗначок + ')');
  }
}

/** Непрозрачность цвета из getComputedStyle: rgb(...) — 1, rgba(..., a) — a,
    color(srgb … / a) — a (так браузер отдаёт итог color-mix). Не цвет — 0. */
function альфа(цвет) {
  const с = String(цвет || '').trim();
  const м = /^(rgba?|color)\((.*)\)$/.exec(с);
  if (!м) return 0;
  const косая = /\/\s*([\d.]+%?)\s*$/.exec(м[2]);
  if (косая) return parseFloat(косая[1]) / (косая[1].endsWith('%') ? 100 : 1);
  const ч = м[2].split(/[\s,]+/).filter(Boolean);
  return м[1] === 'rgba' && ч.length >= 4 ? parseFloat(ч[3]) : 1;
}

