/** Выполняется В СТРАНИЦЕ: зовёт лист так же, как общее/js/сеть.js. */
function подсунуть(св) {
  if (!window.ЛистЕщё || typeof window.ЛистЕщё.досрочно !== 'function') return { ошибка: 'нет window.ЛистЕщё.досрочно' };
  const двери = {
    предложить: function () { return Promise.resolve(св.отказ ? { принято: false, причина: св.отказ } : { принято: true, причина: '' }); },
    голос: function () { return Promise.resolve({ принято: true, причина: '' }); }
  };
  const тексты = {
    строка: { видна: Boolean(св.строка), текст: 'Предложить закончить' },
    плашка: {
      видна: Boolean(св.плашка), текст: (св.имя || 'Аня') + ' предлагает закончить партию', счёт: 'за 2 из 3',
      секунд: св.секунд || 0, отсчёт: function (n) { return n > 0 ? 'ещё ' + n + ' сек.' : ''; },
      кнопки: Boolean(св.кнопки), согласен: 'Согласен', дальше: 'Играть дальше', подпись: св.подпись || ''
    }
  };
  window.ЛистЕщё.досрочно(тексты, двери);
  const открывающая = document.getElementById('кнопка-игра-ещё');
  if (св.открытьЛист) {
    if (!открывающая) return { ошибка: 'нет кнопки «⋯» #кнопка-игра-ещё' };
    открывающая.click();
  }
  if (св.отказ) {
    const строка = document.getElementById('кнопка-лист-игры-досрочно');
    if (!строка) return { ошибка: 'нет строки «Предложить закончить»' };
    строка.click();
  }
  return { ошибка: '' };
}

