/** Выполняется В СТРАНИЦЕ: замеры плашки, строки листа и колонки. */
function замерить() {
  const прям = function (у) { const р = у.getBoundingClientRect(); return { x: р.left, y: р.top, r: р.right, b: р.bottom, w: р.width, h: р.height }; };
  const видно = function (у) {
    if (!у) return false;
    const р = у.getBoundingClientRect();
    return getComputedStyle(у).display !== 'none' && getComputedStyle(у).visibility !== 'hidden' && р.width > 0 && р.height > 0 && !у.closest('.скрыт');
  };
  const м = { W: document.documentElement.clientWidth, H: window.innerHeight, части: {} };
  const пл = document.getElementById('плашка-досрочно');
  м.плашкаЕсть = Boolean(пл);
  м.плашкаВидна = видно(пл);
  if (м.плашкаВидна) {
    м.плашка = прям(пл);
    ['строка', 'текст', 'отсчёт', 'за', 'против', 'подпись', 'причина'].forEach(function (имя) {
      const у = пл.querySelector('.плашка-досрочно__' + имя);
      const з = { есть: Boolean(у), виден: видно(у), текст: у ? у.textContent : '' };
      if (з.виден) {
        Object.assign(з, прям(у));
        з.обрезан = у.scrollWidth > у.clientWidth + 0.5;
        з.ширины = у.scrollWidth + ' / ' + у.clientWidth;
      }
      м.части[имя] = з;
    });
    const ц = document.elementFromPoint((м.плашка.x + м.плашка.r) / 2, (м.плашка.y + м.плашка.b) / 2);
    м.вСерединеПлашки = ц ? (ц.id || ц.className || ц.tagName) : 'ничего';
    м.плашкаСверху = Boolean(ц && пл.contains(ц));
    // Что лежит под плашкой в её середине (первый узел не из плашки).
    const подНей = document.elementsFromPoint((м.плашка.x + м.плашка.r) / 2, (м.плашка.y + м.плашка.b) / 2)
      .filter(function (у) { return !пл.contains(у); })[0];
    м.подПлашкой = подНей ? (подНей.id || String(подНей.className) || подНей.tagName) : 'ничего';
    м.подПлашкойЭкран = подНей && подНей.closest('.экран') ? подНей.closest('.экран').id : '';
    // Непрозрачность и сходство с карточкой лобби (её фон — из того же style.css).
    const св = getComputedStyle(пл);
    м.фон = св.backgroundColor;
    м.непрозрачность = св.opacity;
    // Видимый фон — картинка (градиент), если она есть, иначе цвет.
    const видимыйФон = function (с) { return с.backgroundImage !== 'none' ? с.backgroundImage : с.backgroundColor; };
    м.видимыйФон = видимыйФон(св);
    const карточка = document.querySelector('#экран-лобби .карточка-входа:not(.карточка-входа--играть-онлайн)');
    м.фонКарточки = карточка ? видимыйФон(getComputedStyle(карточка)) : 'карточки не найдено';
    // Высота кнопок голосования (у спрятанной кнопки правило всё равно читается).
    const за = пл.querySelector('.плашка-досрочно__за');
    м.высотаКнопки = за ? parseFloat(getComputedStyle(за).minHeight) : NaN;
    const причина = пл.querySelector('.плашка-досрочно__причина');
    м.причинаФон = причина ? getComputedStyle(причина).backgroundColor : 'нет узла';
    м.причинаЗначок = причина ? getComputedStyle(причина, '::before').content : 'нет узла';
    м.радиус = parseFloat(св.borderTopLeftRadius) || 0;
    // [поверх]: пять точек плашки (углы с отступом 10 и центр текста) — первым узлом
    // в каждой должна быть плашка или её потомок.
    const отступ = 10;
    // Центр текста: первая видимая часть с текстом (у отказа «текста» нет — есть причина).
    const текстУзел = ['текст', 'причина', 'подпись'].map(function (и) { return пл.querySelector('.плашка-досрочно__' + и); })
      .filter(function (у) { return у && видно(у); })[0] || пл;
    const тр = текстУзел.getBoundingClientRect();
    const точкиПоверх = [
      [м.плашка.x + отступ, м.плашка.y + отступ], [м.плашка.r - отступ, м.плашка.y + отступ],
      [м.плашка.x + отступ, м.плашка.b - отступ], [м.плашка.r - отступ, м.плашка.b - отступ],
      [(тр.left + тр.right) / 2, (тр.top + тр.bottom) / 2]
    ];
    м.поверх = точкиПоверх.map(function (т) {
      const первый = document.elementsFromPoint(т[0], т[1])[0];
      return { x: Math.round(т[0]), y: Math.round(т[1]), плашка: Boolean(первый && пл.contains(первый)),
        узел: первый ? (первый.id || String(первый.className) || первый.tagName) : 'ничего' };
    });
  }
  м.вТелеграме = document.documentElement.classList.contains('в-телеграме');
  const верх = document.querySelector('.экран.экран--виден .верх-игры');
  м.верхВиден = видно(верх);
  if (м.верхВиден) м.верх = прям(верх);
  // Колонка: содержимое видимого экрана (его поля) и предел ширины листа «⋯».
  const экран = document.querySelector('.экран.экран--виден');
  м.экран = экран ? экран.id : 'видимого экрана нет';
  if (экран) {
    const с = getComputedStyle(экран), р = экран.getBoundingClientRect();
    м.колонка = { x: р.left + parseFloat(с.paddingLeft), r: р.right - parseFloat(с.paddingRight) };
  }
  const колонкаЛиста = document.querySelector('#лист-игры .лист-ещё__лист');
  м.пределШирины = колонкаЛиста ? parseFloat(getComputedStyle(колонкаЛиста).maxWidth) : NaN;
  const лист = document.getElementById('лист-игры');
  м.листОткрыт = Boolean(лист && !лист.classList.contains('скрыт'));
  const строка = document.getElementById('кнопка-лист-игры-досрочно');
  const меню = document.getElementById('кнопка-лист-игры-меню');
  м.строкаВидна = видно(строка);
  if (м.строкаВидна && меню) {
    м.строка = прям(строка);
    м.меню = прям(меню);
    м.строкаТекст = строка.textContent.trim();
    м.строкаОбрезана = строка.scrollWidth > строка.clientWidth + 0.5;
    // Сразу под первой видимой строкой: следующая видимая строка после «В меню».
    const строки = Array.from(лист.querySelectorAll('.лист-ещё__строка')).filter(видно);
    м.порядок = строки.map(function (у) { return у.id; });
  }
  return м;
}

/** Выполняется В СТРАНИЦЕ: какие узлы экрана «идЭкрана» закрыты плашкой и на сколько.
    Берём только значимые: со своим текстом, картинки/значки, кнопки
    и узлы мест, карт и имён. Вложенное в svg не считаем — значок один. */
function перекрытия(идЭкрана) {
  const пл = document.getElementById('плашка-досрочно');
  const экран = document.getElementById(идЭкрана);
  if (!пл || !экран) return null;
  const р = пл.getBoundingClientRect();
  const итог = [];
  экран.querySelectorAll('*').forEach(function (у) {
    const свг = у.closest('svg');
    if (свг && свг !== у) return;
    const с = getComputedStyle(у);
    if (с.display === 'none' || с.visibility === 'hidden' || у.closest('.скрыт')) return;
    const б = у.getBoundingClientRect();
    if (!б.width || !б.height) return;
    const ш = Math.min(р.right, б.right) - Math.max(р.left, б.left);
    const в = Math.min(р.bottom, б.bottom) - Math.max(р.top, б.top);
    if (ш <= 0.5 || в <= 0.5) return;
    const класс = typeof у.className === 'string' ? у.className.trim() : '';
    const свойТекст = Array.from(у.childNodes).filter(function (н) { return н.nodeType === 3; })
      .map(function (н) { return н.textContent.trim(); }).join(' ').trim();
    const значимый = свойТекст || /^(IMG|SVG|CANVAS|BUTTON)$/i.test(у.tagName) || /карт|мест|игрок|сопер|имя|счёт/.test(класс);
    if (!значимый) return;
    итог.push({
      узел: (у.id ? '#' + у.id : '') + (класс ? '.' + класс.split(/\s+/).join('.') : '') || у.tagName,
      текст: свойТекст.slice(0, 32), ш: Math.round(ш), в: Math.round(в), высота: Math.round(б.height)
    });
  });
  return итог;
}

/** Выполняется В СТРАНИЦЕ: сравнить две картинки (base64 png) по точкам.
    Точки в срезанных скруглением углах пропускаем: там видна страница и у настоящей плашки.
    Возвращает число сравнённых точек, число отличающихся и первую отличающуюся. */
async function сравнитьКартинки([а64, б64, радиусВнутри, порог]) {
  const загрузить = function (б64) {
    return new Promise(function (готово, беда) {
      const к = new Image();
      к.onload = function () { готово(к); };
      к.onerror = function () { беда(new Error('картинка не загрузилась')); };
      к.src = 'data:image/png;base64,' + б64;
    });
  };
  const данные = async function (б64) {
    const к = await загрузить(б64);
    const холст = document.createElement('canvas');
    холст.width = к.naturalWidth; холст.height = к.naturalHeight;
    const кон = холст.getContext('2d');
    кон.drawImage(к, 0, 0);
    return { w: холст.width, h: холст.height, d: кон.getImageData(0, 0, холст.width, холст.height).data };
  };
  const А = await данные(а64), Б = await данные(б64);
  if (А.w !== Б.w || А.h !== Б.h) return { всего: 0, отличий: -1, первая: 'размеры картинок разные' };
  const р = радиусВнутри;
  let всего = 0, отличий = 0, первая = '', макс = 0;
  const мин = { x: 1e9, y: 1e9 }, бб = { x: -1, y: -1 };   // рамка, где нашлись отличия
  for (let y = 0; y < А.h; y++) {
    for (let x = 0; x < А.w; x++) {
      const цx = x < р ? р : (x >= А.w - р ? А.w - р : x);
      const цy = y < р ? р : (y >= А.h - р ? А.h - р : y);
      if ((x + 0.5 - цx) * (x + 0.5 - цx) + (y + 0.5 - цy) * (y + 0.5 - цy) > р * р) continue;
      всего++;
      const и = (y * А.w + x) * 4;
      const разница = Math.max(Math.abs(А.d[и] - Б.d[и]), Math.abs(А.d[и + 1] - Б.d[и + 1]), Math.abs(А.d[и + 2] - Б.d[и + 2]));
      if (разница > порог) {
        отличий++;
        макс = Math.max(макс, разница);
        if (x < мин.x) мин.x = x; if (y < мин.y) мин.y = y; if (x > бб.x) бб.x = x; if (y > бб.y) бб.y = y;
        if (!первая) первая = x + ',' + y;
      }
    }
  }
  return { всего: всего, отличий: отличий, первая: первая, макс: макс, w: А.w, h: А.h,
    рамка: отличий ? мин.x + ',' + мин.y + '–' + бб.x + ',' + бб.y : '' };
}

/** Выполняется В СТРАНИЦЕ: спрятать всё в body, кроме плашки («спрятать»),
    или спрятать одну плашку («плашка»), или вернуть как было («вернуть»). */
function переключитьВид(режим) {
  let с = document.getElementById('замер-точек-стиль');
  if (!с) { с = document.createElement('style'); с.id = 'замер-точек-стиль'; document.head.appendChild(с); }
  // Буквы прозрачные в обоих снимках: сглаживание краёв букв зависит от слоя, на
  // котором их рисуют, и даёт шум в сотню единиц, не связанный с прозрачностью фона.
  const безБукв = '#плашка-досрочно, #плашка-досрочно * { color: transparent !important; text-shadow: none !important; } ';
  if (режим === 'спрятать') с.textContent = безБукв + 'body > *:not(#плашка-досрочно) { visibility: hidden !important; }';
  else if (режим === 'плашка') с.textContent = безБукв + '#плашка-досрочно { visibility: hidden !important; }';
  else if (режим === 'как-есть') с.textContent = безБукв;
  else с.textContent = '';
}

/** Замер [точки]: область плашки (внутри рамки, отступ 2 точки) снимаем дважды —
    над страницей и при спрятанной странице — и сравниваем по точкам.
    Третий снимок (плашка спрятана, страница видна) — справка: сколько точек
    страницы лежит под плашкой и отличается от пустого фона. */
async function замерТочек(страница, м, префиксФайла) {
  if (!м.плашкаВидна) return { всего: 0 };
  const отступ = 2;
  const x = Math.ceil(м.плашка.x + отступ), y = Math.ceil(м.плашка.y + отступ);
  const clip = { x: x, y: y, width: Math.floor(м.плашка.r - отступ) - x, height: Math.floor(м.плашка.b - отступ) - y };
  const радиусВнутри = Math.max(0, Math.round(м.радиус) - отступ);
  const снять = async function () { return (await страница.screenshot({ clip: clip })).toString('base64'); };
  await страница.evaluate(переключитьВид, 'как-есть');
  await страница.waitForTimeout(150);
  const какЕсть = await снять();
  await страница.evaluate(переключитьВид, 'спрятать');
  await страница.waitForTimeout(150);
  const безСтраницы = await снять();
  await страница.evaluate(переключитьВид, 'вернуть');
  await страница.evaluate(переключитьВид, 'плашка');
  await страница.waitForTimeout(150);
  const безПлашки = await снять();
  await страница.evaluate(переключитьВид, 'вернуть');
  const итог = await страница.evaluate(сравнитьКартинки, [какЕсть, безСтраницы, радиусВнутри, ПОРОГ_ТОЧКИ]);
  итог.страницаПодПлашкой = await страница.evaluate(сравнитьКартинки, [безПлашки, безСтраницы, радиусВнутри, ПОРОГ_ТОЧКИ]);
  итог.область = clip.width + '×' + clip.height;
  if (итог.отличий !== 0 && префиксФайла) {   // при провале кладём обе картинки рядом со снимками
    fs.writeFileSync(префиксФайла + '-точки-а-как-есть.png', Buffer.from(какЕсть, 'base64'));
    fs.writeFileSync(префиксФайла + '-точки-б-без-страницы.png', Buffer.from(безСтраницы, 'base64'));
  }
  return итог;
}

const внутри = function (а, б, доп) { const д = доп === undefined ? 0.5 : доп; return а.x >= б.x - д && а.y >= б.y - д && а.r <= б.r + д && а.b <= б.b + д; };
const кратко = function (р) { return р ? Math.round(р.x) + ',' + Math.round(р.y) + '–' + Math.round(р.r) + ',' + Math.round(р.b) : 'нет'; };

