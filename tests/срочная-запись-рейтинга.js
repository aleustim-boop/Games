#!/usr/bin/env node
'use strict';

/* =====================================================================
   СРОЧНАЯ ЗАПИСЬ РЕЙТИНГА: очки за партию должны лечь на диск сразу,
   а не через пять секунд.

   Жалоба ревьюера, из которой родилась эта проверка: server/рейтинг.js
   держал начисленные очки в памяти и писал их на диск отложенно
   (ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ = 5000 мс). Штатная остановка сервера дописывает
   всё честно, но падение или жёсткое выключение в эти пять секунд стирает
   очки за только что сыгранную партию — человек выиграл, увидел итог,
   а в таблице рейтинга очков нет.

   КАК ПРОВЕРЯЕМ «упало сразу после партии», не дожидаясь настоящего
   падения и не ожидая реальных пяти секунд: партия засчитывается в
   ОТДЕЛЬНОМ процессе node, который завершается через process.exit(0)
   сразу же после учестьПартию — без вызова дописать(). Отложенный
   таймер (см. записатьПогодя) помечен .unref() и точно так же не
   переживает жёсткое завершение процесса. Если очки должны были лечь
   на диск немедленно (записатьСрочно) — writeFileSync успевает отработать
   ДО exit(0), и файл на диске есть. Если код вернулся к старой отложенной
   записи — файла нет вовсе, ровно то, на что жаловался ревьюер.

   ЧТО ПРОВЕРЯЕМ:
     1) партия, где человек реально обыграл человека (очки > 0) —
        после «падения» сразу после конца партии очки на диске ЕСТЬ;
     2) партия без очков (человек обыграл лёгкого бota, цена 0) — при
        том же самом «падении» на диске по-прежнему НИЧЕГО НЕТ: мелочь
        осталась отложенной, мы не начали писать файл на каждый чих.

   УМЕЕТ ЛИ ОНА КРАСНЕТЬ. node tests/срочная-запись-рейтинга.js --сломать
   берёт временную копию server/рейтинг.js и возвращает срочную запись
   очков обратно к пятисекундной отложенной (записатьПогодя вместо
   записатьСрочно) — ровно та поломка, о которой предупреждал ревьюер.
   На такой копии пункт (1) обязан провалиться: очков на диске сразу
   после «падения» уже не будет.

   Боевых данных не касается: копия server/ и папка данных — во временных
   каталогах (mkdtempSync), партия каждый раз считается в отдельном
   дочернем процессе node, чтобы «падение сразу после exit» было настоящим,
   а не догадкой по логике кода.

   Запуск:
     node tests/срочная-запись-рейтинга.js             (обычный прогон)
     node tests/срочная-запись-рейтинга.js --сломать   (обязан провалиться)
   Выход 0 — провалов нет, 1 — провал (смотреть строки «ПРОВАЛ» в выводе).
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const СЛОМАТЬ = process.argv.includes('--сломать');

const ПРОВЕРКИ = [];
function проверить(имя, условие, подробности) {
  ПРОВЕРКИ.push({ имя: имя, ошибка: условие ? null : (подробности || 'условие не выполнено') });
}

/* Все временные папки этого прогона (копия server/ и по одной у каждого
   дочернего раннера) — чтобы убрать их за собой в самом конце, а не
   оставлять мусор во временной папке ОС на каждый запуск. */
const ВСЕ_ВРЕМЕННЫЕ_ПАПКИ = [];

/** Своя временная папка с заданным префиксом — и сразу на учёт для уборки. */
function новаяВременнаяПапка(префикс) {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), префикс));
  ВСЕ_ВРЕМЕННЫЕ_ПАПКИ.push(папка);
  return папка;
}

/* Убираем СВОИ временные папки по любому выходу процесса —
   process.on('exit') срабатывает и на process.exit(), и на непойманную
   ошибку. Раньше эти папки никогда не удалялись и копились на диске. */
process.on('exit', function () {
  for (const папка of ВСЕ_ВРЕМЕННЫЕ_ПАПКИ) {
    try { fs.rmSync(папка, { recursive: true, force: true, maxRetries: 3 }); } catch (е) { /* не страшно */ }
  }
});

/** Своя копия server/ во временной папке — боевой код и боевые данные не трогаем. */
function подготовитьКопиюСервера() {
  const врем = новаяВременнаяПапка('срочная-запись-рейтинга-');
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(врем, 'server'), { recursive: true });
  /* server/игры/умолчания.js берёт список игр из общего js/игры-реестр.js —
     без него копия сервера не загрузится. */
  fs.mkdirSync(path.join(врем, 'js'), { recursive: true });
  fs.copyFileSync(path.join(КОРЕНЬ, 'js', 'игры-реестр.js'), path.join(врем, 'js', 'игры-реестр.js'));
  return path.join(врем, 'server', 'рейтинг.js');
}

/**
 * Порча копии: возвращает срочную запись очков обратно к пятисекундной
 * отложенной — ровно та регрессия, от которой предостерегал ревьюер.
 */
function испортитьКопию(путьКРейтингу) {
  const исходник = fs.readFileSync(путьКРейтингу, 'utf8');
  const было = '    if (начисленоВсего > 0) записатьСрочно();\r\n    else записатьПогодя();';
  if (исходник.indexOf(было) === -1) {
    throw new Error('не нашёл строку для порчи — код server/рейтинг.js изменился, поправьте tests/срочная-запись-рейтинга.js');
  }
  const испорчено = исходник.replace(было,
    '    записатьПогодя(); /* ИСПОРЧЕНО ПРОВЕРКОЙ tests/срочная-запись-рейтинга.js --сломать: очки снова ждут 5 секунд */');
  fs.writeFileSync(путьКРейтингу, испорчено, 'utf8');
}

/**
 * Содержимое раннера: в отдельном процессе засчитывает одну партию и
 * СРАЗУ завершается через process.exit(0), без дописать() — это и есть
 * модель «сервер упал в первую же миллисекунду после конца партии».
 */
function кодРаннера(папкаДанных, путьКРейтингу, застольем) {
  return [
    "process.env.GAMES_DATA = " + JSON.stringify(папкаДанных) + ";",
    "const рейтинг = require(" + JSON.stringify(путьКРейтингу) + ");",
    "рейтинг.включитьЗапись();",
    "рейтинг.учестьПартию('дурак', " + JSON.stringify(застольем) + ");",
    "process.exit(0);"
  ].join('\n');
}

/** Засчитать партию в отдельном процессе и вернуть, что осталось на диске. */
function засчитатьВОтдельномПроцессе(путьКРейтингу, застольем) {
  const врем = новаяВременнаяПапка('срочная-запись-рейтинга-раннер-');
  const папкаДанных = path.join(врем, 'данные');
  const файлРаннера = path.join(врем, 'раннер.js');
  fs.writeFileSync(файлРаннера, кодРаннера(папкаДанных, путьКРейтингу, застольем), 'utf8');

  execFileSync(process.execPath, [файлРаннера], { stdio: 'pipe' });

  const файлРейтинга = path.join(папкаДанных, 'рейтинг.json');
  if (!fs.existsSync(файлРейтинга)) return null;
  return JSON.parse(fs.readFileSync(файлРейтинга, 'utf8'));
}

/** Очки игрока в прочитанном файле рейтинга (или null, если записи нет). */
function очкиИгрока(данные, номер) {
  if (!данные || !Array.isArray(данные.игроки)) return null;
  const запись = данные.игроки.find(function (з) { return з.номер === номер; });
  return запись ? запись.очки : null;
}

/* -----------------------------------------------------------------------
   main
   ----------------------------------------------------------------------- */

const путьКРейтингу = подготовитьКопиюСервера();
if (СЛОМАТЬ) испортитьКопию(путьКРейтингу);

/* Сценарий 1: человек обыграл человека — реальные очки, «важное». */
const победительЧеловек = { номер: 1001, имя: 'Аня', этоБот: false, победил: true };
const проигравшийЧеловек = { номер: 1002, имя: 'Боря', этоБот: false, победил: false };
const данные1 = засчитатьВОтдельномПроцессе(путьКРейтингу, [победительЧеловек, проигравшийЧеловек]);
const очки1001 = очкиИгрока(данные1, 1001);

проверить(
  'очки за победу над человеком есть на диске сразу после «падения» процесса',
  очки1001 === 10,
  данные1 === null
    ? 'файл рейтинга вообще не появился — очки потерялись, как и предупреждал ревьюер'
    : 'на диске очки игрока 1001: ' + очки1001 + ' (ждали 10)'
);

/* Сценарий 2: человек обыграл лёгкого бота — цена партии 0, «мелочь».
   Проверяем это только на НЕиспорченной копии: смысл сценария — убедиться,
   что мы не стали писать на диск каждый чих, а не в том, что он должен
   провалиться на сломанной копии (там и без того всё уходит в отложенную
   запись — сценарий 2 там ничего нового не покажет). */
if (!СЛОМАТЬ) {
  const победительНадБотом = { номер: 2001, имя: 'Вера', этоБот: false, победил: true };
  const лёгкийБот = { номер: null, имя: 'Бот', этоБот: true, уровень: 'лёгкий', победил: false };
  const данные2 = засчитатьВОтдельномПроцессе(путьКРейтингу, [победительНадБотом, лёгкийБот]);

  проверить(
    'партия без очков (лёгкий бот) не пишется на диск немедленно — мелочь по-прежнему отложена',
    данные2 === null,
    'файл рейтинга появился сразу, хотя очков партия не начисляла: ' + JSON.stringify(данные2)
  );
}

console.log('');
let провалов = 0;
for (const п of ПРОВЕРКИ) {
  if (п.ошибка) {
    провалов++;
    console.log('  ПРОВАЛ ' + п.имя + ': ' + п.ошибка);
  } else {
    console.log('  ок     ' + п.имя);
  }
}
console.log('');
console.log('Итого проверок: ' + ПРОВЕРКИ.length + ', провалов: ' + провалов);
process.exit(провалов > 0 ? 1 : 0);
