/* =====================================================================
   Проверка тупиков: может ли игрок оказаться в положении,
   где ходить нечем, а кнопки на экране не показаны.

   Что именно ловим (по правилам показа кнопок из js/game.js):
     — фаза «атака»: кнопок нет вообще, значит у атакующего ОБЯЗАНА быть
       хотя бы одна карта, которую разрешено положить. Иначе — тупик,
       партия встанет намертво;
     — фаза «защита»: должна быть доступна кнопка «Беру» (она есть всегда);
     — фазы «подкидывание»/«докидывание»: есть кнопка «Бито».

   Запуск: node tests/проверка-тупиков.js [сколько партий]
   ===================================================================== */

'use strict';

const игра = require(require('path').join(__dirname, '..', 'js', 'game.js'));
const ПАРТИЙ = Number(process.argv[2]) || 2000;

let зерно = 777;
Math.random = function () {
  зерно = (зерно * 1103515245 + 12345) % 2147483648;
  return зерно / 2147483648;
};

const тупики = [];
let проверокФазыАтаки = 0;
let пустыхРукВАтаке = 0;

/** Игрок ходит наугад любым разрешённым способом — так состояний перебирается больше. */
function случайныйХод(п, игрок) {
  const фаза = игра.фаза(п);
  const рука = п.руки[игрок];
  if (фаза === 'защита') {
    const варианты = [];
    п.стол.forEach((пара, iПары) => {
      if (пара.защита) return;
      рука.forEach((к, iК) => { if (игра.бьёт(к, пара.атака, п.козырь)) варианты.push([iПары, iК]); });
    });
    if (варианты.length === 0 || Math.random() < 0.3) { игра.объявитьБеру(п); return; }
    const в = варианты[Math.floor(Math.random() * варианты.length)];
    игра.отбить(п, в[0], в[1]);
    return;
  }
  const годные = [];
  for (let i = 0; i < рука.length; i++) if (игра.можноПоложить(п, рука[i])) годные.push(i);
  if (годные.length === 0 || (фаза !== 'атака' && Math.random() < 0.45)) { игра.завершитьПодход(п); return; }
  игра.положитьВАтаку(п, игрок, годные[Math.floor(Math.random() * годные.length)]);
}

for (let н = 1; н <= ПАРТИЙ; н++) {
  зерно = н * 8191 + 3;
  const п = игра.создатьПартию();
  let шагов = 0;

  while (!п.завершена && шагов++ < 500) {
    const фаза = игра.фаза(п);
    const ходит = игра.ктоХодит(п);

    if (фаза === 'атака') {
      проверокФазыАтаки++;
      const рука = п.руки[ходит];
      if (рука.length === 0) {
        пустыхРукВАтаке++;
        тупики.push('партия ' + н + ': ход «' + ходит + '», стол пуст, а в руке НЕТ карт и кнопок на экране не будет');
      } else {
        let есть = false;
        for (const к of рука) if (игра.можноПоложить(п, к)) { есть = true; break; }
        if (!есть) {
          тупики.push('партия ' + н + ': ход «' + ходит + '», стол пуст, в руке ' + рука.length +
            ' карт, но ни одну положить нельзя — на экране не будет ни карт для хода, ни кнопки. ' +
            'В колоде ' + п.колода.length + ', у соперника ' + п.руки[игра.защищается(п)].length + ' карт');
        }
      }
    }

    if (тупики.length > 8) break;
    случайныйХод(п, ходит);
  }

  if (!п.завершена) тупики.push('партия ' + н + ': не закончилась за 500 ходов');
  if (тупики.length > 8) break;
}

console.log('=== Проверка тупиков ===');
console.log('партий: ' + ПАРТИЙ + ', положений «стол пуст, надо ходить» проверено: ' + проверокФазыАтаки);
if (тупики.length === 0) {
  console.log('тупиков не найдено: когда стол пуст, у ходящего всегда есть чем сходить');
  process.exit(0);
} else {
  console.log('НАЙДЕНЫ ТУПИКИ:');
  тупики.forEach(т => console.log('  - ' + т));
  process.exit(1);
}
