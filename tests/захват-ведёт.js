// Проверка Р16: метка «ведёт» в капсулах игроков «Захвата» (очков СТРОГО больше всех) и класс пульта на время раскрытия.
// Запуск:  node tests/захват-ведёт.js            — обычный прогон (без браузера)
//          node tests/захват-ведёт.js --сломать  — портит КОПИИ стола и оформления во временной папке, требует провала
//          node tests/захват-ведёт.js --браузер  — граница пилюль «+N» на 390×844 в настоящем браузере (Playwright); с --сломать — порча верхКарты
// Доводы для ломающих запусков: --файл <путь к столу>, --css <путь к style-захват.css>.
// Разметка и поддельный документ — из tests/захват-основа-стола.js (берёт настоящий захват.html).
'use strict';
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const а = process.argv.slice(2);
const довод = (имя) => { const и = а.indexOf(имя); return и === -1 ? null : а[и + 1]; };
const путьСтола = довод('--файл') || path.join(КОРЕНЬ, 'js', 'захват-стол.js');
const путьCss = довод('--css') || path.join(КОРЕНЬ, 'style-захват.css');

if (а.includes('--браузер')) {
  if (а.includes('--сломать')) браузерПорча();
  else браузерПрогон().then((код) => process.exit(код), (е) => { console.log('ПРОВАЛ: обход упал — ' + String(е && е.stack || е).split('\n').slice(0, 3).join(' / ')); process.exit(1); });
} else if (а.includes('--сломать')) {
  сломать();
} else {
  process.exit(прогон());
}

function прогон() {
  const с = require('./захват-основа-стола.js')(путьСтола);
  const { Правила, сделатьДокумент, сделатьПартию, узлыКласса, ЗахватСтол, проверка } = с;
  const оч = { a: 9, b: 9, c: 9, d: 9, e: 9, f: 9 };
  const прежниеОчки = Правила.очки;
  const прежняяВИгре = Правила.вИгре;
  Правила.очки = function (п, к) { return оч[к]; };
  try {
    const партия = сделатьПартию();
    const документ = сделатьДокумент();
    const стол = ЗахватСтол.создать({ документ: документ, рисункиЕсть: false, слушатели: {} });
    const заново = () => стол.начатьРаунд(партия, 'a', { имена: {} });
    const ведущие = () => узлыКласса(документ.корень, 'захват-игрок--ведёт');
    // Ключ игрока, на чьей капсуле метка (капсулы идут в порядке партия.игроки).
    const ктоПомечен = () => {
      const фишки = документ.getElementById('захват-игроки').children;
      return партия.игроки.filter((к, н) => фишки[н] && фишки[н].classList.contains('захват-игрок--ведёт'));
    };
    заново();
    проверка('капсулы игроков есть (ноль найденного — провал)', документ.getElementById('захват-игроки').children.length >= 6);
    проверка('все по 9 — метки нет ни у кого', ведущие().length === 0);
    оч.c = 10; заново();
    проверка('у одного 10, у прочих 9 — метка ровно у одного', ведущие().length === 1);
    проверка('метка именно у того, у кого 10 (игрок c)', ктоПомечен().join() === 'c', ктоПомечен().join());
    оч.d = 10; заново();
    проверка('10 и 10 — метки нет ни у кого', ведущие().length === 0);
    оч.d = 9; оч.c = 10; заново();
    проверка('снова один лидер — метка вернулась', ведущие().length === 1);
    // Все по нулю (первый раунд до раскрытия) — ведущего нет, хотя «0 > …» ни у кого.
    for (const к of Object.keys(оч)) оч[к] = 0;
    оч.a = 0; заново();
    проверка('у всех ноль — метки нет', ведущие().length === 0);
    // Один оставшийся с нулём очков (остальные вне игры) тоже не «ведёт»: ноль — это ещё не лидерство.
    Правила.вИгре = function (п, к) { return к === 'a' && прежняяВИгре(п, к); };
    заново();
    проверка('единственный в игре с нулём очков — метки нет', ведущие().length === 0, ктоПомечен().join());
    Правила.вИгре = прежняяВИгре;
    оч.a = 1; заново();
    проверка('у одного 1, у прочих 0 — метка есть', ведущие().length === 1 && ктоПомечен().join() === 'a', ктоПомечен().join());
    // Игрок вне игры не считается соперником: лидер при втором месте выбывшего всё равно ведёт (и наоборот — выбывший не ведёт).
    for (const к of Object.keys(оч)) оч[к] = 9;
    оч.b = 20; оч.c = 10;
    Правила.вИгре = function (п, к) { return к !== 'b' && прежняяВИгре(п, к); };
    заново();
    проверка('выбывший с наибольшими очками не ведёт и не мешает лидеру', ктоПомечен().join() === 'c', ктоПомечен().join());
    Правила.вИгре = прежняяВИгре;
    // Конец партии — метки нет.
    оч.b = 9; оч.c = 10; заново();
    стол.задатьКонец(true);
    проверка('после конца партии метки нет', ведущие().length === 0);
    стол.задатьКонец(false);
    // Класс пульта на время раскрытия.
    const пульт = документ.getElementById('захват-пульт');
    стол.задатьРаскрытие(true);
    проверка('в раскрытии у пульта класс --раскрытие', пульт.classList.contains('захват-пульт--раскрытие'));
    стол.задатьРаскрытие(false);
    проверка('после раскрытия класс снят', !пульт.classList.contains('захват-пульт--раскрытие'));

    // Оформление: слово «ведёт» рисует css, «Отменить» в раскрытии прячется, не сдвигая раскладку.
    const css = fs.readFileSync(путьCss, 'utf8');
    проверка('css: у метки «ведёт» есть слово (content: "ведёт")', /\.захват-игрок--ведёт::after\s*\{[^}]*content:\s*"ведёт"/.test(css));
    проверка('css: слово «ведёт» — салатовый акцент', /\.захват-игрок--ведёт::after\s*\{[^}]*color:\s*var\(--сб-акцент\)/.test(css));
    проверка('css: в раскрытии «Отменить» прячется через visibility',
      /#захват-пульт\.захват-пульт--раскрытие\s+#захват-отменить\s*\{\s*visibility:\s*hidden/.test(css));
  } finally {
    Правила.очки = прежниеОчки;
    Правила.вИгре = прежняяВИгре;
  }
  const итог = с.счёт();
  console.log('Итого проверок: ' + (итог.пройдено + итог.провалы.length) + ', провалов: ' + итог.провалы.length);
  return итог.провалы.length ? 1 : 0;
}

function сломать() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-ведёт-'));
  const стол = fs.readFileSync(path.join(КОРЕНЬ, 'js', 'захват-стол.js'), 'utf8');
  const css = fs.readFileSync(path.join(КОРЕНЬ, 'style-захват.css'), 'utf8');
  const порчи = [
    ['стол', 'при равенстве метка остаётся (>=)', 'if (лучший === null || очки > лучший.очки)', 'if (лучший === null || очки >= лучший.очки)'],
    ['стол', 'ведёт и тот, у кого ноль очков', 'лучший.очки > 0 ? лучший.ключ : null', 'лучший.очки >= 0 ? лучший.ключ : null'],
    ['стол', 'метка живёт и после конца партии', 'if (!п || состояние.конец) return null;', 'if (!п) return null;'],
    ['стол', 'выбывшие участвуют в споре за лидерство', 'if (!Правила.вИгре(п, ключ)) return;\n        const очки', 'const очки'],
    ['стол', 'класс метки переименован', "класс(фишка, 'захват-игрок--ведёт', ведущий !== null && ключ === ведущий);", "класс(фишка, 'захват-игрок--ведут', ведущий !== null && ключ === ведущий);"],
    ['стол', 'метка у всех, а не у лидера', "ведущий !== null && ключ === ведущий);   // слово", "ведущий !== null);   // слово"],
    ['стол', 'класс пульта в раскрытии не ставится', "класс(пульт, 'захват-пульт--раскрытие', !!состояние.раскрытие);", "класс(пульт, 'захват-пульт--раскрытие', false);"],
    ['css', 'слово «ведёт» пропало', 'content: "ведёт"; grid-area', 'content: ""; grid-area'],
    ['css', 'слово «ведёт» не салатовое', 'letter-spacing: 0.02em; color: var(--сб-акцент);', 'letter-spacing: 0.02em;'],
    ['css', '«Отменить» в раскрытии не прячется', '#захват-пульт.захват-пульт--раскрытие #захват-отменить { visibility: hidden; }', '']
  ];
  let красных = 0;
  порчи.forEach(function (п, н) {
    const исходник = п[0] === 'стол' ? стол : css;
    if (исходник.split(п[2]).length !== 2) { console.log('ПРОВАЛ — место порчи не найдено ровно один раз: ' + п[1]); return; }
    let порченое = исходник.replace(п[2], () => п[3]);
    const путь = path.join(папка, 'п' + н + (п[0] === 'стол' ? '.js' : '.css'));
    // Порченый стол берёт настоящие правила по полному пути: их очки подменяет сама проверка.
    if (п[0] === 'стол') порченое = порченое.replace(/require\('\.\/(захват-[^']+)'\)/g, (_, имя) => 'require(' + JSON.stringify(path.join(КОРЕНЬ, 'js', имя)) + ')');
    fs.writeFileSync(путь, порченое);
    const р = spawnSync(process.execPath, [__filename, п[0] === 'стол' ? '--файл' : '--css', путь], { encoding: 'utf8' });
    const красная = р.status === 1 && /ПРОВАЛ/.test(р.stdout);
    if (красная) красных++;
    console.log((красная ? 'КРАСНЕЕТ' : 'НЕ КРАСНЕЕТ (плохо)') + ' — ' + п[1] + ' (код ' + р.status + ')');
  });
  const чист = spawnSync(process.execPath, [__filename], { encoding: 'utf8' });
  console.log('Обычный прогон: код ' + чист.status + ' — ' + чист.stdout.trim().split('\n').pop());
  console.log('Красных: ' + красных + ' из ' + порчи.length);
  process.exit(красных === порчи.length && чист.status === 0 ? 0 : 1);
}

/* ---------- браузерная часть (Р18в): пилюли «+N» не выходят за окно карты на 390×844 ---------- */

// Пилюля «+N» над шайбой, у которой верх окна карты выше, должна встать ПОД шайбу (Р16: верхКарты считает окно,
// а не рамку узла). Приём: две верхние шайбы карты отдаём человеку, ставим по войску — и меряем рамки пилюль.
// Зерно случайных чисел задано, карта одна и та же при каждом запуске.
async function браузерПрогон() {
  const http = require('http');
  const { chromium, подготовитьПодделку, перехватить } = require('./браузер-робот.js');
  const подмена = довод('--страница-стол');
  const ТИПЫ = {
    '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'application/javascript; charset=utf-8',
    '.json': 'application/json', '.svg': 'image/svg+xml', '.webp': 'image/webp', '.png': 'image/png', '.jpg': 'image/jpeg',
    '.woff2': 'font/woff2', '.woff': 'font/woff', '.ttf': 'font/ttf'
  };
  const сервер = http.createServer((запрос, ответ) => {
    let п = '/';
    try { п = decodeURIComponent(запрос.url.split('?')[0]); } catch (_) { /* как есть */ }
    const файл = path.join(КОРЕНЬ, п === '/' ? 'index.html' : п);
    const внутри = !path.relative(КОРЕНЬ, файл).startsWith('..');
    if (внутри && fs.existsSync(файл) && fs.statSync(файл).isFile()) {
      ответ.writeHead(200, { 'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'application/octet-stream' });
      ответ.end(fs.readFileSync(файл));
    } else { ответ.writeHead(404); ответ.end('нет такого файла'); }
  });
  await new Promise((г) => сервер.listen(0, '127.0.0.1', г));
  const порт = сервер.address().port;
  console.log('Сервер проверки: порт ' + порт + ', PID ' + process.pid + (подмена ? ', стол подменён копией: ' + подмена : ''));
  let всего = 0, провалов = 0;
  const проверить = (имя, условие, подробности) => {
    всего++;
    if (!условие) { провалов++; console.log('ПРОВАЛ: ' + имя + (подробности ? ' — ' + подробности : '')); }
    return !!условие;
  };
  const браузер = await chromium.launch();
  try {
    const контекст = await браузер.newContext({ viewport: { width: 390, height: 844 } });
    const страница = await контекст.newPage();
    await подготовитьПодделку(страница, {});
    const ошибки = [];
    страница.on('console', (с) => { if (с.type() === 'error' && (с.location().url || '').indexOf('telegram-web-app.js') === -1) ошибки.push(с.text()); });
    страница.on('pageerror', (е) => ошибки.push('необработанная ошибка: ' + е.message));
    if (подмена) {
      const тело = fs.readFileSync(подмена);
      await перехватить(страница, /\/js\/захват-стол\.js(\?|$)/, (путь) => путь.fulfill({ status: 200, contentType: 'application/javascript; charset=utf-8', body: тело }));
    }
    await страница.addInitScript(() => { try { localStorage.setItem('zahvat-learned', '1'); } catch (_) { /* пусто */ } });
    await страница.goto('http://127.0.0.1:' + порт + '/захват.html', { waitUntil: 'load' });
    await страница.waitForTimeout(800);
    // Партия на заданном зерне; две верхние по экрану области отданы человеку (после первого запуска видно, где они).
    const мои = await страница.evaluate(() => {
      const ген = (с) => { let з = с >>> 0; return () => { з = (з + 0x6D2B79F5) | 0; let т = Math.imul(з ^ (з >>> 15), 1 | з); т = (т + Math.imul(т ^ (т >>> 7), 61 | т)) ^ т; return ((т ^ (т >>> 14)) >>> 0) / 4294967296; }; };
      Math.random = ген(21);
      const Р = window.ЗахватПравила;
      const партия = Р.новаяПартия({ игроки: ['человек', 'бот-1', 'бот-2'], люди: ['человек'], сейчас: Date.now(), раундовЗахвата: 15 }, Math.random);
      const выбор = { мест: 3, уровень: 'обычный', раундовЗахвата: 15, новичок: false };
      window.ЗахватЭкран.начатьПартиюСБотами(партия, выбор);
      const ряд = [];
      партия.хозяева.forEach((х, н) => { const т = window.ЗахватЭкран.гдеОбласть(н); if (х && т) ряд.push([т.y, н]); });
      ряд.sort((а, б) => а[0] - б[0]);
      const верхние = ряд.slice(0, 3).map((а) => а[1]);
      верхние.forEach((н) => { партия.хозяева[н] = 'человек'; });
      window.ЗахватЭкран.начатьПартиюСБотами(партия, выбор);
      return партия.хозяева.map((х, н) => (х === 'человек' ? н : -1)).filter((н) => н >= 0);
    });
    await страница.waitForTimeout(1200);
    проверить('у человека есть области для расстановки (ноль найденного — провал)', мои.length >= 3, 'областей ' + мои.length);
    for (const н of мои) {
      // Координаты берём заново перед каждым касанием: верх окна карты мог сдвинуться (метка «ведёт» у капсулы).
      const т = await страница.evaluate((н) => window.ЗахватЭкран.гдеОбласть(н), н);
      if (т) { await страница.mouse.click(т.x, т.y); await страница.waitForTimeout(120); }
    }
    // Щипок двумя пальцами (настоящие события указателя на карте): зум 1,1 с серединой внизу уводит верхний ряд вверх,
    // «+N» над верхними шайбами оказывается выше окна карты — их обязана поставить под шайбу.
    await страница.evaluate(() => {
      const к = document.getElementById('захват-карта');
      const е = (т, id, x, y) => к.dispatchEvent(new PointerEvent(т, { pointerId: id, clientX: x, clientY: y, bubbles: true, pointerType: 'touch' }));
      е('pointerdown', 11, 145, 600); е('pointerdown', 12, 245, 600);
      е('pointermove', 11, 140, 600); е('pointermove', 12, 250, 600);
      е('pointerup', 11, 140, 600); е('pointerup', 12, 250, 600);
    });
    await страница.waitForTimeout(300);
    const з = await страница.evaluate(() => {
      const о = window.ЗахватСтол.замеритьОкно(document);
      const к = document.getElementById('захват-карта').getBoundingClientRect();
      return {
        окно: о, верх: о ? к.top + о.верх : null, низ: о ? к.top + о.низ : null, картаВерх: k_(к),
        пилюли: Array.from(document.querySelectorAll('.захват-пилюля')).map((у) => {
          const р = у.getBoundingClientRect();
          return { текст: (у.textContent || '').trim(), верх: р.top, низ: р.bottom, лево: р.left, право: р.right,
            под: у.classList.contains('захват-пилюля--под'), видна: р.width > 0 && р.height > 0 };
        })
      };
      function k_(к) { return к.top; }
    });
    проверить('окно карты замерено (ноль — провал)', !!з.окно, JSON.stringify(з.окно));
    const видимые = з.пилюли.filter((п) => п.видна);
    проверить('на карте есть пилюли «+N» (ноль найденных — провал)', видимые.length >= 3, 'видимых ' + видимые.length);
    console.log('    окно карты на экране: от ' + Math.round(з.верх) + ' до ' + Math.round(з.низ) + ' px; пилюль ' + видимые.length +
      ', из них под шайбой ' + видимые.filter((п) => п.под).length + '; верхняя пилюля начинается с ' + Math.round(Math.min.apply(null, видимые.map((п) => п.верх))) + ' px');
    const выше = видимые.filter((п) => п.верх < з.верх - 0.5);
    проверить('ни одна пилюля не выше верха окна карты', выше.length === 0,
      'выше окна (верх окна ' + Math.round(з.верх) + '): ' + выше.map((п) => '«' + п.текст + '» с ' + Math.round(п.верх)).join(', '));
    const ниже = видимые.filter((п) => п.низ > з.низ + 0.5);
    проверить('ни одна пилюля не ниже низа окна карты', ниже.length === 0,
      'ниже окна (низ окна ' + Math.round(з.низ) + '): ' + ниже.map((п) => '«' + п.текст + '» до ' + Math.round(п.низ)).join(', '));
    проверить('пилюли целиком по ширине экрана', видимые.every((п) => п.лево >= -0.5 && п.право <= 390.5));
    проверить('хоть одна пилюля встала под шайбу — защита от верха окна действительно сработала (ноль — провал)', видимые.some((п) => п.под));
    проверить('консоль чистая', ошибки.length === 0, ошибки.join(' | '));
    await контекст.close();
  } finally {
    await браузер.close();
    сервер.close();
  }
  console.log('Итого проверок: ' + всего + ', провалов: ' + провалов);
  return провалов ? 1 : 0;
}

// Порча КОПИИ стола во временной папке: верхКарты снова берёт рамку узла, а не окно карты (как до Р16).
// Страница подгружает копию подменой ответа; настоящий js/захват-стол.js не трогается. Должно покраснеть.
function браузерПорча() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-ведёт-браузер-'));
  const стол = fs.readFileSync(путьСтола, 'utf8');
  const было = 'if (окно) return у.getBoundingClientRect().top + окно.верх;';
  if (стол.split(было).length !== 2) { console.log('ПРОВАЛ — место порчи (верхКарты) не найдено ровно один раз'); process.exit(1); }
  const копия = path.join(папка, 'захват-стол-старый-верх.js');
  fs.writeFileSync(копия, стол.replace(было, () => ''));
  const р = spawnSync(process.execPath, [__filename, '--браузер', '--страница-стол', копия], { encoding: 'utf8' });
  const красная = р.status === 1 && /ПРОВАЛ: ни одна пилюля не выше верха окна карты/.test(р.stdout || '');
  console.log((красная ? 'КРАСНЕЕТ' : 'НЕ КРАСНЕЕТ (плохо)') + ' — верхКарты по рамке узла вместо окна (код ' + р.status + ')');
  if (!красная) console.log((р.stdout || '') + (р.stderr || ''));
  else console.log((р.stdout || '').split('\n').filter((с) => /^ПРОВАЛ|^Итого|окно карты на экране/.test(с)).join('\n'));
  process.exit(красная ? 0 : 1);
}
