/* =====================================================================
   ЛЕНТА НОВОСТЕЙ — ПРОВЕРКА СТРОКИ ВНИЗУ ЭКРАНА.

   Что за лента. Игра помнит восемь последних новостей стола («Бот 3 ходит
   3♥», «Бот 6 отбил 3♦ картой 4♦»). Внизу экрана в строке подсказки стоит
   столько последних, сколько влезает рядом с напоминанием «что делать
   сейчас», — обычно одна-две. Нажатие по строке открывает плашку «Что было»
   со всем списком.

   Что здесь проверяется — четыре вещи, и все на живом экране:

   1. НАПОМИНАНИЕ «ЧТО ДЕЛАТЬ» НЕ ВЫТЕСНЯЕТСЯ. Это главное: новости —
      приятная добавка, а напоминание — единственное место, где написано,
      чего от человека ждут. Считаем так, как велел исполнитель: смотрим
      на последний кусок строки (куски разделены знаком « · »). Если он —
      новость из копилки, значит напоминания в строке нет. Такое допустимо
      ровно в одном случае, и он старый: пара «новость · напоминание»
      физически не влезает в строку, и пока новость свежая, строка её.
      Отличаем одно от другого перемером: подставляем пару в саму строку
      и спрашиваем игру её же меркой «влезлоВСтроку». Не влезла — старое
      исключение. Влезла — НОВАЯ ПОТЕРЯ, и это поломка.

   2. МНОГОТОЧИЕ НЕ ВРЁТ. Знак «…» слева означает «есть непоказанное».
      Он не имеет права стоять, когда в копилке ровно столько новостей,
      сколько уже показано в строке.

   3. КОПИЛКА НЕ ПЕРЕПОЛНЯЕТСЯ. Больше восьми новостей игра помнить
      не должна.

   4. СТРОКА НЕ СРЕЗАНА. Отдельно смотрим на то, что вправду написано
      в строке сейчас: помещается ли оно целиком. Обрубок вроде «Бот 3
      берёт карт…» — поломка независимо от всех правил выше.

   Своей мерки «сколько влезает» здесь НЕТ и быть не должно: спрашиваем
   игру через её же двери — «последниеСобытия», «сколькоНовостейВСтроке»
   и «влезлоВСтроку». Пересказ чужой мерки в этом проекте уже трижды
   расходился с настоящей.

   Как пользоваться (из консоли браузера, партия идёт):
       ЛентаМера.включить();
       ... играем (руками или автоигроком) ...
       ЛентаМера.отчёт();
       ЛентаМера.выключить();
   ===================================================================== */

(function () {
  'use strict';

  const ШАГ_ЗАМЕРА = 70;          // как часто заглядываем в строку, мс
  const РАЗДЕЛИТЕЛЬ = ' · ';
  const ЗНАК_ЕСТЬ_ЕЩЁ = '…';
  const ПРЕДЕЛ_КОПИЛКИ = 8;       // столько новостей игра обещает помнить

  function эл(id) { return document.getElementById(id); }

  /* Тот же узел, который меряет сама игра: внутри коробки подсказки лежит
     span с текстом, и высоту спрашивают именно у него. */
  function узелСтроки() {
    const коробка = эл('подсказка');
    if (!коробка) return null;
    return эл('подсказка-текст') || коробка;
  }

  /** Достать из страницы то, что объявлено через let (window его не знает). */
  function глянуть(имя) {
    try { return (0, eval)(имя); } catch (е) { return undefined; }
  }

  function идётПартия() {
    const партия = глянуть('партия');
    const экран = эл('экран-игры');
    return Boolean(партия && !партия.завершена &&
                   экран && экран.classList.contains('экран--виден'));
  }

  const счёт = {
    следим: false,
    таймер: null,
    шагов: 0,                 // сколько РАЗНЫХ состояний строки увидели
    сНовостями: 0,            // из них — с новостями в строке
    безНапоминания: 0,        // строк, где напоминания «что делать» не оказалось
    староеИсключение: 0,      // ... и пара вправду не влезала (так и задумано)
    новаяПотеря: 0,           // ... а пара влезала — вот это поломка
    сЗнаком: 0,               // строк со знаком «…»
    знакСоврал: 0,            // ... и прятать было нечего
    переполнений: 0,          // копилка длиннее восьми
    максКопилки: 0,
    срезано: 0,               // строка не помещается целиком (обрубок на экране)
    примеры: [],              // до 12 подробных случаев для отчёта
    прошлаяСтрока: null
  };

  function запомнитьПример(что, подробности) {
    if (счёт.примеры.length >= 12) return;
    счёт.примеры.push(Object.assign({ что: что }, подробности));
  }

  /**
   * Влезет ли в строку заданный текст. Подставляем его в тот же самый узел,
   * меряем игровой меркой и возвращаем прежний текст на место.
   *
   * Подменяем именно текст и ничего больше: пометки (огонёк «ваш ход»,
   * жирная свежесть) остаются как были — они меняют место под слова,
   * и снимать их значило бы мерить не то, что человек видит.
   */
  function влезетЛи(текст, узел) {
    const мерка = глянуть('влезлоВСтроку');
    if (typeof мерка !== 'function') return null;
    const прежний = узел.textContent;
    узел.textContent = текст;
    let ответ;
    try { ответ = мерка(текст, узел); }
    finally { узел.textContent = прежний; }
    return ответ;
  }

  /** Один взгляд на строку внизу экрана. */
  function заглянуть() {
    if (!идётПартия()) return;
    const узел = узелСтроки();
    if (!узел) return;
    const строка = (узел.textContent || '').trim();
    if (!строка || строка === счёт.прошлаяСтрока) return;
    счёт.прошлаяСтрока = строка;
    счёт.шагов++;

    const копилка = window.последниеСобытия ? window.последниеСобытия() : [];
    const показано = window.сколькоНовостейВСтроке ? window.сколькоНовостейВСтроке() : 0;
    if (копилка.length > счёт.максКопилки) счёт.максКопилки = копилка.length;
    if (копилка.length > ПРЕДЕЛ_КОПИЛКИ) {
      счёт.переполнений++;
      запомнитьПример('копилка длиннее восьми', { сколько: копилка.length });
    }
    if (показано > 0) счёт.сНовостями++;

    const куски = строка.split(РАЗДЕЛИТЕЛЬ);

    /* --- 2. Многоточие. Стоит первым куском и только если есть что прятать. */
    if (куски[0] === ЗНАК_ЕСТЬ_ЕЩЁ) {
      счёт.сЗнаком++;
      if (копилка.length <= показано) {
        счёт.знакСоврал++;
        запомнитьПример('многоточие соврало: прятать нечего',
                        { строка: строка, вКопилке: копилка.length, показано: показано });
      }
    }

    /* --- 4. Строка не срезана: то, что написано, помещается целиком. */
    const мерка = глянуть('влезлоВСтроку');
    if (typeof мерка === 'function' && мерка(строка, узел) === false) {
      счёт.срезано++;
      запомнитьПример('строка не помещается — на экране обрубок',
                      { строка: строка, знаков: строка.length });
    }

    /* --- 1. Напоминание «что делать». Последний кусок не должен быть новостью. */
    const последний = куски[куски.length - 1];
    if (копилка.indexOf(последний) < 0) return;   // напоминание на месте — всё хорошо

    счёт.безНапоминания++;
    const действие = глянуть('текстДействия');
    let текстНапоминания = '';
    try { текстНапоминания = типичноеДействие(действие); }
    catch (е) { текстНапоминания = ''; }
    if (!текстНапоминания) {
      запомнитьПример('напоминания в строке нет, а спросить игру, каким оно ' +
                      'должно быть, не вышло', { строка: строка });
      return;
    }
    const пара = копилка[копилка.length - 1] + РАЗДЕЛИТЕЛЬ + текстНапоминания;
    const влезла = влезетЛи(пара, узел);
    if (влезла === false) {
      счёт.староеИсключение++;
      return;
    }
    счёт.новаяПотеря++;
    запомнитьПример('НОВАЯ ПОТЕРЯ: напоминание пропало, хотя пара влезала',
                    { строка: строка, пара: пара, знаков: пара.length });
  }

  function типичноеДействие(действие) {
    if (typeof действие !== 'function') return '';
    return String(действие() || '');
  }

  window.ЛентаМера = {
    включить: function () {
      if (счёт.следим) return 'уже слежу';
      счёт.следим = true;
      счёт.таймер = setInterval(заглянуть, ШАГ_ЗАМЕРА);
      return 'слежу за строкой подсказки';
    },
    выключить: function () {
      clearInterval(счёт.таймер);
      счёт.следим = false;
      return 'перестал следить';
    },
    сбросить: function () {
      счёт.шагов = 0; счёт.сНовостями = 0; счёт.безНапоминания = 0;
      счёт.староеИсключение = 0; счёт.новаяПотеря = 0;
      счёт.сЗнаком = 0; счёт.знакСоврал = 0;
      счёт.переполнений = 0; счёт.максКопилки = 0; счёт.срезано = 0;
      счёт.примеры = []; счёт.прошлаяСтрока = null;
      return 'счёт обнулён';
    },
    отчёт: function () {
      return {
        шаговСтроки: счёт.шагов,
        изНихСНовостями: счёт.сНовостями,
        безНапоминания: счёт.безНапоминания,
        изНихСтароеИсключение: счёт.староеИсключение,
        изНихНоваяПотеря: счёт.новаяПотеря,
        строкСоЗнаком: счёт.сЗнаком,
        знакСоврал: счёт.знакСоврал,
        переполненийКопилки: счёт.переполнений,
        максимумКопилки: счёт.максКопилки,
        строкаСрезана: счёт.срезано,
        примеры: счёт.примеры
      };
    }
  };
})();
