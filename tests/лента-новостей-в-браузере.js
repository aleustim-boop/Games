/* =====================================================================
   ЛЕНТА НОВОСТЕЙ — ПРОВЕРКА СТРОКИ ВНИЗУ ЭКРАНА.

   Что за лента. Игра помнит восемь последних новостей стола («Бот 3 ходит
   3♥», «Бот 6 отбил 3♦ картой 4♦»). Нажатие по строке внизу открывает
   плашку «Что было» со всем списком.

   ЧТО ИЗМЕНИЛОСЬ. Раньше эти новости стояли и в самой строке внизу.
   По просьбе владельца их оттуда убрали целиком: строка снова говорит
   ровно об одном — что делать сейчас. Поэтому отсюда ушли два правила,
   которые сторожили новости В СТРОКЕ: «многоточие не врёт» (знака «…»
   больше не бывает) и счёт показанных новостей (он теперь всегда ноль).
   Копилка при этом жива и нужна — её показывает плашка.

   Что здесь проверяется — три вещи, и все на живом экране:

   1. НАПОМИНАНИЕ «ЧТО ДЕЛАТЬ» НЕ ВЫТЕСНЯЕТСЯ. Это главное: напоминание —
      единственное место, где написано, чего от человека ждут. Спрашиваем
      игру, каким оно должно быть сейчас («текстДействия»), и смотрим,
      стоит ли оно в строке. Нет — значит его вытеснило то, что игра
      ставит слева сама: свежий отказ на нажатие или объявление в начале
      партии. Такое допустимо ровно в одном случае: пара «сообщение ·
      напоминание» физически не влезает в строку. Отличаем перемером —
      подставляем пару в саму строку и спрашиваем игру её же меркой
      «влезлоВСтроку». Не влезла — старое исключение. Влезла — НОВАЯ
      ПОТЕРЯ, и это поломка.

      Здесь же и грабли, на которые уже наступили: прежде это правило
      искало новость последним куском строки. Новости из строки убрали —
      и правило перестало срабатывать вообще, то есть молча пропускало бы
      настоящую потерю, оставаясь зелёным.

   2. КОПИЛКА НЕ ПЕРЕПОЛНЯЕТСЯ. Больше восьми новостей игра помнить
      не должна.

   3. СТРОКА НЕ СРЕЗАНА. Отдельно смотрим на то, что вправду написано
      в строке сейчас: помещается ли оно целиком. Обрубок вроде «Бот 3
      берёт карт…» — поломка независимо от правил выше.

   Своих мерок и своих пересказов здесь НЕТ и быть не должно: и текст,
   и мерка спрашиваются у самой игры — «текстДействия»,
   «сообщениеДляСтроки», «последниеСобытия», «влезлоВСтроку». Свой
   пересказ чужой мерки в этом проекте расходился с настоящей уже
   пять раз.

   Как пользоваться (из консоли браузера, партия идёт):
       ЛентаМера.включить();
       ... играем (руками или автоигроком) ...
       ЛентаМера.отчёт();
       ЛентаМера.выключить();
   ===================================================================== */

(function () {
  'use strict';

  const ШАГ_ЗАМЕРА = 70;          // как часто заглядываем в строку, мс
  const РАЗДЕЛИТЕЛЬ = ' · ';
  const ПРЕДЕЛ_КОПИЛКИ = 8;       // столько новостей игра обещает помнить

  function эл(id) { return document.getElementById(id); }

  /* Тот же узел, который меряет сама игра: внутри коробки подсказки лежит
     span с текстом, и высоту спрашивают именно у него. */
  function узелСтроки() {
    const коробка = эл('подсказка');
    if (!коробка) return null;
    return эл('подсказка-текст') || коробка;
  }

  /** Достать из страницы то, что объявлено через let (window его не знает). */
  function глянуть(имя) {
    try { return (0, eval)(имя); } catch (е) { return undefined; }
  }

  function идётПартия() {
    const партия = глянуть('партия');
    const экран = эл('экран-игры');
    return Boolean(партия && !партия.завершена &&
                   экран && экран.classList.contains('экран--виден'));
  }

  const счёт = {
    следим: false,
    таймер: null,
    шагов: 0,                 // сколько РАЗНЫХ состояний строки увидели
    безНапоминания: 0,        // строк, где напоминания «что делать» не оказалось
    староеИсключение: 0,      // ... и пара вправду не влезала (так и задумано)
    новаяПотеря: 0,           // ... а пара влезала — вот это поломка
    переполнений: 0,          // копилка длиннее восьми
    максКопилки: 0,
    срезано: 0,               // строка не помещается целиком (обрубок на экране)
    примеры: [],              // до 12 подробных случаев для отчёта
    прошлаяСтрока: null
  };

  function запомнитьПример(что, подробности) {
    if (счёт.примеры.length >= 12) return;
    счёт.примеры.push(Object.assign({ что: что }, подробности));
  }

  /**
   * Влезет ли в строку заданный текст. Подставляем его в тот же самый узел,
   * меряем игровой меркой и возвращаем прежний текст на место.
   *
   * Подменяем именно текст и ничего больше: пометки (огонёк «ваш ход»,
   * жирная свежесть) остаются как были — они меняют место под слова,
   * и снимать их значило бы мерить не то, что человек видит.
   */
  function влезетЛи(текст, узел) {
    const мерка = глянуть('влезлоВСтроку');
    if (typeof мерка !== 'function') return null;
    const прежний = узел.textContent;
    узел.textContent = текст;
    let ответ;
    try { ответ = мерка(текст, узел); }
    finally { узел.textContent = прежний; }
    return ответ;
  }

  /** Один взгляд на строку внизу экрана. */
  function заглянуть() {
    if (!идётПартия()) return;
    const узел = узелСтроки();
    if (!узел) return;
    const строка = (узел.textContent || '').trim();
    if (!строка || строка === счёт.прошлаяСтрока) return;
    счёт.прошлаяСтрока = строка;
    счёт.шагов++;

    /* --- 2. Копилка не переполняется. Сама копилка жива и нужна: её целиком
       показывает плашка «Что было». А вот в строку новости больше не попадают
       вовсе, поэтому спрашивать «сколько их показано» стало не о чем. */
    const копилка = window.последниеСобытия ? window.последниеСобытия() : [];
    if (копилка.length > счёт.максКопилки) счёт.максКопилки = копилка.length;
    if (копилка.length > ПРЕДЕЛ_КОПИЛКИ) {
      счёт.переполнений++;
      запомнитьПример('копилка длиннее восьми', { сколько: копилка.length });
    }

    /* --- 3. Строка не срезана: то, что написано, помещается целиком. */
    const мерка = глянуть('влезлоВСтроку');
    if (typeof мерка === 'function' && мерка(строка, узел) === false) {
      счёт.срезано++;
      запомнитьПример('строка не помещается — на экране обрубок',
                      { строка: строка, знаков: строка.length });
    }

    /* --- 1. Напоминание «что делать» на месте?

       Спрашиваем игру, каким оно должно быть прямо сейчас, и смотрим, стоит
       ли оно в строке. Раньше здесь искали новость последним куском — но
       новостей в строке больше не бывает, и та проверка не срабатывала уже
       никогда, то есть молча пропускала бы настоящую потерю. Вытеснить
       напоминание теперь может только то, что игра ставит слева сама:
       свежий отказ на нажатие или объявление в начале партии. Забота
       осталась прежней и она главная — человеку всегда должно быть
       написано, чего от него ждут. */
    const напоминание = спроситьИгру(глянуть('текстДействия'));
    if (!напоминание) return;                    // игра и сама молчит — сравнивать не с чем
    if (строка === напоминание) return;          // напоминание и есть вся строка
    const куски = строка.split(РАЗДЕЛИТЕЛЬ);
    if (куски[куски.length - 1] === напоминание) return;   // стоит справа, как и задумано

    счёт.безНапоминания++;
    const сообщение = спроситьИгру(глянуть('сообщениеДляСтроки'));
    if (!сообщение) {
      запомнитьПример('напоминания в строке нет, и слева тоже ничего нет — ' +
                      'откуда взялась эта строка, непонятно',
                      { строка: строка, ждали: напоминание });
      return;
    }
    const пара = сообщение + РАЗДЕЛИТЕЛЬ + напоминание;
    if (влезетЛи(пара, узел) === false) {
      счёт.староеИсключение++;                   // пара не влезла — это старое, дозволенное
      return;
    }
    счёт.новаяПотеря++;
    запомнитьПример('НОВАЯ ПОТЕРЯ: напоминание пропало, хотя пара влезала',
                    { строка: строка, пара: пара, знаков: пара.length });
  }

  /**
   * Позвать функцию самой игры и взять её ответ строкой.
   * Нет такой функции или она споткнулась — считаем, что ответа нет.
   * Через неё спрашиваем и напоминание («текстДействия»), и то, что игра
   * ставит слева («сообщениеДляСтроки»): своих пересказов здесь нет.
   */
  function спроситьИгру(чтоСпросить) {
    if (typeof чтоСпросить !== 'function') return '';
    try { return String(чтоСпросить() || ''); } catch (е) { return ''; }
  }

  window.ЛентаМера = {
    включить: function () {
      if (счёт.следим) return 'уже слежу';
      счёт.следим = true;
      счёт.таймер = setInterval(заглянуть, ШАГ_ЗАМЕРА);
      return 'слежу за строкой подсказки';
    },
    выключить: function () {
      clearInterval(счёт.таймер);
      счёт.следим = false;
      return 'перестал следить';
    },
    сбросить: function () {
      счёт.шагов = 0; счёт.безНапоминания = 0;
      счёт.староеИсключение = 0; счёт.новаяПотеря = 0;
      счёт.переполнений = 0; счёт.максКопилки = 0; счёт.срезано = 0;
      счёт.примеры = []; счёт.прошлаяСтрока = null;
      return 'счёт обнулён';
    },
    отчёт: function () {
      return {
        шаговСтроки: счёт.шагов,
        безНапоминания: счёт.безНапоминания,
        изНихСтароеИсключение: счёт.староеИсключение,
        изНихНоваяПотеря: счёт.новаяПотеря,
        переполненийКопилки: счёт.переполнений,
        максимумКопилки: счёт.максКопилки,
        строкаСрезана: счёт.срезано,
        примеры: счёт.примеры
      };
    }
  };
})();
