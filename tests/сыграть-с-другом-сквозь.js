async function главное() {
  const начало = Date.now();
  // Сторож: если что-то всё же повиснет — не молчать бесконечно, а упасть.
  setTimeout(function () {
    console.log('  ПРОВАЛ проверка не уложилась в 240 с — что-то повисло');
    process.exit(1);
  }, 240000).unref();
  сервера.оснасткаДляПроверки(ТОКЕН, function (метод) {
    if (метод === 'savePreparedInlineMessage') return { ok: true, result: { id: 'готово-' + Date.now() } };
    return { ok: true, result: {} };
  });
  const сервер = сервера.создатьСервер();
  await new Promise(function (готово, беда) {
    сервер.once('error', беда);
    сервер.listen(ПОРТ, '127.0.0.1', готово);
  });
  console.log('Тестовый сервер поднят в этом процессе на порту ' + ПОРТ + ', PID ' + process.pid +
    ' (боевой 8790 не трогаем); данные: ' + process.env.ДАННЫЕ_ИГРЫ);

  try {
    await случайПолныйПуть();
    await случайДругБезПодписи();
    await случайПричиныОтказа();
    await случайДругоеУстройство();
    await случайОтменаПриглашения();
    await случайРеванш();
  } catch (сбой) {
    провалов++;
    console.log('  ПРОВАЛ проверка упала: ' + (сбой && сбой.stack || сбой));
  } finally {
    ВСЕ_КЛИЕНТЫ.forEach(function (погасить) { погасить(); });
    // Живые соединения (keep-alive от fetch) не дают close() дождаться конца.
    if (typeof сервер.closeAllConnections === 'function') сервер.closeAllConnections();
    await new Promise(function (готово) { сервер.close(готово); });
    сервера.оснасткаДляПроверки();
    // Убираем за собой временные папки (данные сервера и копию кода при ломающем запуске).
    try { fs.rmSync(process.env.ДАННЫЕ_ИГРЫ, { recursive: true, force: true }); } catch (е) { /* не страшно */ }
    if (ЛОМАЕМ) { try { fs.rmSync(КОРЕНЬ_СЕРВЕРА, { recursive: true, force: true }); } catch (е) { /* не страшно */ } }
  }

  console.log('\nЧисло действий игрока по каждой игре (хозяин / друг):');
  for (const игра of Object.keys(ДЕЙСТВИЯ)) {
    console.log('  ' + игра + ': хозяин ' + ДЕЙСТВИЯ[игра].хозяин + ', друг ' + ДЕЙСТВИЯ[игра].друг);
  }

  if (всего < 60) {
    провалов++;
    console.log('  ПРОВАЛ выполнено подозрительно мало проверок: ' + всего);
  }
  console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов +
    ', время прогона ' + Math.round((Date.now() - начало) / 1000) + ' с');
  process.exit(провалов > 0 ? 1 : 0);
}

главное();
