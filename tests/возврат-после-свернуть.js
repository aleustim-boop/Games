/**
 * Поднять страницу в песочнице.
 * п: { корень, страница ('mines.html'), search, hash, ls, ss, telegram, реестр (bool),
 *      telegramJs (bool), узлы: { id: { hidden, ... } } }
 */
function поднять(п) {
  const часы = { t: НАЧАЛО };
  const таймеры = [];
  let следующийНомер = 1;
  const html = new Узел('html');
  const head = new Узел('head');
  const body = new Узел('body');
  html.appendChild(head); html.appendChild(body);
  const слушателиДокумента = {};
  const слушателиОкна = {};
  const переходы = [];
  const локальная = поддельнаяПамять(п.ls);
  const сессия = поддельнаяПамять(п.ss);

  const документ = {
    readyState: 'complete', documentElement: html, head: head, body: body,
    createElement: () => new Узел(''),
    getElementById(id) {
      return [html, head, body].concat(html.все()).find(у => у.id === id) || null;
    },
    querySelector: () => null, querySelectorAll: сел => html.querySelectorAll(сел),
    addEventListener(имя, ф) { (слушателиДокумента[имя] = слушателиДокумента[имя] || []).push(ф); },
    removeEventListener(имя, ф) {
      if (слушателиДокумента[имя]) слушателиДокумента[имя] = слушателиДокумента[имя].filter(х => х !== ф);
    }
  };

  const ПоддельнаяДата = class extends Date {
    constructor(...а) { if (а.length) super(...а); else super(часы.t); }
    static now() { return часы.t; }
  };

  const имя = п.страница || 'index.html';
  const окно = {
    localStorage: локальная, sessionStorage: сессия,
    location: {
      pathname: '/' + encodeURI(имя === 'index.html' && п.корневойАдрес ? '' : имя),
      search: п.search || '', hash: п.hash || '',
      replace(куда) { переходы.push(куда); }
    },
    addEventListener(и, ф) { (слушателиОкна[и] = слушателиОкна[и] || []).push(ф); },
    removeEventListener(и, ф) { if (слушателиОкна[и]) слушателиОкна[и] = слушателиОкна[и].filter(х => х !== ф); },
    dispatchEvent(е) {
      if (п.telegram) { if (е.type === 'перед-закрытием') п.telegram.метка.приСобытии = п.telegram.читатьМетку(); }
      (слушателиОкна[е.type] || []).slice().forEach(ф => ф(е));
      return true;
    },
    matchMedia: () => ({ matches: false, addEventListener() {}, addListener() {} }),
    getComputedStyle: () => ({ display: 'block', visibility: 'visible' })
  };
  if (п.telegram) {
    п.telegram.читатьМетку = () => локальная.getItem(КЛЮЧ_МЕТКИ);
    окно.Telegram = { WebApp: п.telegram };
  }
  окно.window = окно;

  const планировать = (ф, мс, повтор) => {
    const номер = следующийНомер++;
    таймеры.push({ номер, при: часы.t + Math.max(0, Number(мс) || 0), мс: Math.max(1, Number(мс) || 1), повтор, ф });
    return номер;
  };
  const снять = номер => { const i = таймеры.findIndex(т => т.номер === номер); if (i >= 0) таймеры.splice(i, 1); };

  const песочница = {
    window: окно, document: документ, localStorage: локальная, sessionStorage: сессия,
    CustomEvent: class { constructor(тип) { this.type = тип; } },
    console: { log() {}, warn() {}, error() {} },
    navigator: { userAgent: 'проверка' },
    Date: ПоддельнаяДата,
    setTimeout: (ф, мс) => планировать(ф, мс, false), clearTimeout: снять,
    setInterval: (ф, мс) => планировать(ф, мс, true), clearInterval: снять,
    parseFloat, isFinite, encodeURIComponent, decodeURIComponent
  };
  песочница.globalThis = песочница;
  vm.createContext(песочница);

  const сбои = [];
  const грузить = файл => {
    try { vm.runInContext(fs.readFileSync(файл, 'utf8'), песочница, { filename: файл }); }
    catch (с) { сбои.push(path.basename(файл) + ': ' + с.message); }
  };

  // Узлы страницы (кнопки «продолжить», экраны дурака)
  Object.keys(п.узлы || {}).forEach(id => {
    const у = new Узел(id);
    Object.assign(у, п.узлы[id].свойства || {});
    (п.узлы[id].классы || []).forEach(к => у.классы.add(к));
    body.appendChild(у);
  });

  if (п.telegramJs) грузить(path.join(п.корень, 'общее', 'js', 'telegram.js'));
  if (п.реестр) грузить(path.join(п.корень, 'общее', 'js', 'игры-реестр.js'));
  грузить(path.join(п.корень, 'общее', 'js', 'возврат-после-свернуть.js'));

  /** Прокрутить поддельное время вперёд, запуская таймеры в срок. */
  function прокрутить(мс) {
    const цель = часы.t + мс;
    for (let защита = 0; защита < 100000; защита++) {
      const готовые = таймеры.filter(т => т.при <= цель).sort((а, б) => а.при - б.при || а.номер - б.номер);
      if (!готовые.length) break;
      const т = готовые[0];
      часы.t = Math.max(часы.t, т.при);
      if (т.повтор) т.при += т.мс; else снять(т.номер);
      try { т.ф(); } catch (с) { сбои.push('таймер: ' + с.message); }
    }
    часы.t = цель;
  }
  /** Касание пальцем: события «до всего» страницы. */
  function коснуться(тип) {
    (слушателиДокумента[тип || 'touchstart'] || []).slice().forEach(ф => ф({ type: тип || 'touchstart' }));
  }
  return { окно, документ, локальная, сессия, переходы, сбои, прокрутить, коснуться, узел: id => документ.getElementById(id), часы };
}

const метка = (стр, возраст, д) => JSON.stringify({ p: стр, d: !!д, t: НАЧАЛО - (возраст === undefined ? 1000 : возраст) });
