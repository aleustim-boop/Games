const ПОРЧИ = [
  { имя: '(а) в возврат-после-свернуть.js убрано стирание метки перед переходом', файл: 'общее/js/возврат-после-свернуть.js',
    от: "    стеретьПамять('localStorage', КЛЮЧ_МЕТКИ);\n    var метка = разобратьМетку(сырое);", на: '    var метка = разобратьМетку(сырое);' },
  { имя: '(б) в telegram.js убран вызов записи метки', файл: 'общее/js/telegram.js',
    от: '      записатьМеткуВозврата();\n', на: '' },
  { имя: '(в) на одной странице (mines.html) убрано подключение файла', файл: 'mines.html',
    правка: т => т.replace(/<script src="общее\/js\/возврат-после-свернуть\.js[^"]*"><\/script>/, '') }
];

function копияПроекта(из, куда) {
  require('./пути-проекта.js').создатьПапкиКода(куда);
  require('./пути-проекта.js').скопироватьКод(из, куда, 'js');
  fs.readdirSync(из).filter(ф => ф.endsWith('.html')).forEach(ф => fs.copyFileSync(path.join(из, ф), path.join(куда, ф)));
}

// ---------------------------------------------------------------- запуск

const аргументы = process.argv.slice(2);
const номерСломать = аргументы.indexOf('--сломать');
const доводКорня = аргументы.find(а => а.startsWith('--корень='));

(async () => {
  if (номерСломать < 0) {
    const корень = доводКорня ? path.resolve(доводКорня.slice('--корень='.length)) : КОРЕНЬ_ПРОЕКТА;
    const итог = await запустить(корень, true);
    console.log('Итого проверок: ' + итог.проверок + ', провалов: ' + итог.провалы.length);
    process.exit(итог.провалы.length ? 1 : 0);
  }
  const папка = аргументы[номерСломать + 1];
  if (!папка) { console.log('Укажи временную папку: --сломать <папка>'); process.exit(2); }
  let всего = 0, провалов = 0, непокраснели = 0;
  for (let i = 0; i < ПОРЧИ.length; i++) {
    const порча = ПОРЧИ[i];
    const место = path.join(папка, 'порча-' + i);
    копияПроекта(КОРЕНЬ_ПРОЕКТА, место);
    const файл = path.join(место, порча.файл);
    const было = fs.readFileSync(файл, 'utf8').replace(/\r\n/g, '\n');
    let стало;
    if (порча.правка) { стало = порча.правка(было); }
    else {
      if (было.split(порча.от).length !== 2) { непокраснели++; console.log('  НЕТ МЕСТА ДЛЯ ПОРЧИ (ровно одно совпадение нужно): ' + порча.имя); continue; }
      стало = было.split(порча.от).join(порча.на);
    }
    if (стало === было) { непокраснели++; console.log('  НЕТ МЕСТА ДЛЯ ПОРЧИ (текст не изменился): ' + порча.имя); continue; }
    fs.writeFileSync(файл, стало);
    const итог = await запустить(место, false);
    всего += итог.проверок; провалов += итог.провалы.length;
    if (итог.провалы.length) console.log('  краснеет: ' + порча.имя + ' (провалов ' + итог.провалы.length + '; первый: ' + итог.провалы[0] + ')');
    else { непокраснели++; console.log('  НЕ КРАСНЕЕТ: ' + порча.имя); }
  }
  console.log('Итого проверок: ' + всего + ', провалов: ' + провалов);
  process.exit(непокраснели ? 3 : 1);
})().catch(с => { console.log('проверка сломалась: ' + с.stack); process.exit(2); });
