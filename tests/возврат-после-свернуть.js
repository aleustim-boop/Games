/* =====================================================================
   ВОЗВРАТ ПОСЛЕ «СВЕРНУТЬ» — проверка без браузера (песочница vm).

   Что случилось: у Telegram нет команды «свернуть», есть только «закрыть».
   Поэтому общее/js/telegram.js перед закрытием пишет в память метку resume_at
   «где закрылись», а общее/js/возврат-после-свернуть.js при следующем открытии
   возвращает человека на ту же игру и нажимает «продолжить».

   Что проверяем (поддельные страница, память, адрес и Telegram):
     а) кнопка «Свернуть» пишет метку с верной страницей ДО события
        «перед-закрытием» и ДО close; close упал или его нет — метки нет;
        дурак (экран лобби виден на index.html) — d:true, витрина — d:false;
        игрок снова коснулся экрана (приложение живо) — метка снимается;
     б) витрина: свежая метка → переход на нужную страницу, метка стёрта,
        флаг resume_pending стоит; метка старше 12 ч, из будущего, мусор →
        перехода нет, метка стёрта; приглашение в адресе → перехода нет;
        спрятанная игра и неизвестная страница → перехода нет;
        d:true на index.html → index.html?game=durak, d:false → перехода нет;
        повторный заход без метки — перехода нет (нет зацикливания);
     в) страница игры: по флагу кнопка «продолжить» нажата ровно один раз,
        флаг снят; скрытая кнопка — 0 нажатий за 8 секунд; касание до
        появления кнопки — 0 нажатий; без флага — 0; приоритет
        «кнопка-вернуться-в-игру»;
     г) КАЖДАЯ html-страница корня с общее/js/telegram.js подключает и
        общее/js/возврат-после-свернуть.js ПОСЛЕ него, а index.html — ещё и после
        общее/js/игры-реестр.js (ноль найденных страниц — провал);
     д) каждая кнопка из списка КНОПКИ_ПРОДОЛЖИТЬ реально встречается как id
        в какой-нибудь html или js проекта (ноль или не нашлась — провал).

   Запуск:                node tests/возврат-после-свернуть.js
   Другая папка проекта:  node tests/возврат-после-свернуть.js --корень=<папка>
   Ломающий запуск (портит КОПИИ во временной папке, не проект):
       node tests/возврат-после-свернуть.js --сломать <папка>
   Каждая порча обязана покраснеть; выход 1 — краснеет как надо,
   выход 3 — какая-то порча НЕ покраснела (проверка — украшение).
   Итог — строкой «Итого проверок: N, провалов: M».
   ===================================================================== */

