function прочитатьСписокКнопок(текст) {
  const м = /var КНОПКИ_ПРОДОЛЖИТЬ = \[([\s\S]*?)\];/.exec(текст);
  if (!м) return [];
  const имена = [];
  const ре = /'([^']+)'/g;
  let х;
  // Комментарии после запятых тоже в кавычках не бывают, но на всякий случай вырезаем их
  const чисто = м[1].replace(/\/\/[^\n]*/g, '');
  while ((х = ре.exec(чисто))) имена.push(х[1]);
  return имена;
}

function экраниро(с) { return с.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }

