function ловец(страница) {
  const красные = [];
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const где = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js/.test(где)) return;
    красные.push(м.text() + ' [' + decodeURIComponent(где) + ']');
  });
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  return красные;
}

/** Что сейчас на столе — всё, что обещано макетом. Работает в странице. */
function слепокСтола() {
  const к = (id) => document.getElementById(id);
  const видна = (у) => Boolean(у) && !у.classList.contains('скрыт') && у.offsetParent !== null;
  const кнопка = (id) => {
    const у = к(id);
    if (!у) return null;
    return { текст: у.textContent.trim(), нельзя: у.disabled, видна: видна(у), действие: у.getAttribute('data-действие') };
  };
  const экран = к('экран-игры');
  const дети = [...экран.children].map((у) => у.id || у.className.split(' ')[0]);
  const панель = к('панель-кнопок');
  return {
    режим: ((к('режим-партии') || {}).textContent || '').trim(),
    статус: ((к('статус-хода') || {}).textContent || '').trim(),
    акцент: к('статус-хода') ? к('статус-хода').classList.contains('пилюля--акцент') : null,
    яХожу: к('строка-меня') ? к('строка-меня').classList.contains('строка-игрока--ходит') : null,
    мойХод: typeof сейчасМойХод === 'function' && typeof партия !== 'undefined' && партия && !партия.завершена ? сейчасМойХод() : null,
    беру: кнопка('кнопка-беру'), бито: кнопка('кнопка-завершить'), перевод: кнопка('кнопка-перевести'),
    бросить: кнопка('кнопка-бросить'), сказать: кнопка('кнопка-эмоции'),
    видимыхВПанели: панель ? [...панель.children].filter(видна).map((у) => у.id) : [],
    порядок: дети,
    плашек: document.querySelectorAll('#соперники .соперник').length,
    полосаВидна: видна(к('соперники')),
    строкаСоперникаВидна: видна(к('рука-бота'))
  };
}

/** Правила панели по макету для одного слепка — список нарушений. */
function нарушенияПанели(с) {
  const беды = [];
  if (!с.беру || !с.беру.видна) беды.push('«Взять» не видна (должна стоять всегда, нельзя — выключена)');
  const наМестеБито = [с.бито, с.перевод, с.бросить].filter((к) => к && к.видна);
  if (наМестеБито.length !== 1) беды.push('на месте «Бито» ' + наМестеБито.length + ' кнопок: ' + наМестеБито.map((к) => к.текст).join(', '));
  if (с.бито && с.бито.видна) {
    const ждём = { 'бито': 'Бито', 'готово': 'Готово', 'пас': 'Пас' }[с.бито.действие];
    if (!ждём) беды.push('у кнопки на месте «Бито» незнакомое data-действие «' + с.бито.действие + '»');
    else if (с.бито.текст !== ждём) беды.push('надпись «' + с.бито.текст + '», а data-действие «' + с.бито.действие + '»');
  }
  if (с.видимыхВПанели.length > 3) беды.push('в панели больше трёх кнопок: ' + с.видимыхВПанели.join(', '));
  if (с.мойХод === true && (!с.акцент || !с.яХожу)) беды.push('ход ваш, а пилюля без акцента или строка «Вы» не подсвечена');
  return беды;
}

