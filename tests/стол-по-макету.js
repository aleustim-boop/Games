/** Сделать один ход за человека, если он есть. Возвращает, что нажали. */
async function ход(страница) {
  return страница.evaluate(() => {
    const к = (id) => document.getElementById(id);
    const можно = [...document.querySelectorAll('#карты-человека .карта--можно')];
    const выбрана = document.querySelector('#карты-человека .карта--выбрана');
    const цель = document.querySelector('#стол .пара--цель');
    if (выбрана && цель) { цель.click(); return 'бью'; }
    if (!к('кнопка-беру').disabled) {
      if (можно.length) { можно[0].click(); return 'поднял'; }
      к('кнопка-беру').click(); return 'взял';
    }
    const бито = к('кнопка-завершить');
    if (!бито.disabled && !бито.classList.contains('скрыт')) {
      if (можно.length && Math.random() < 0.4) { можно[0].click(); return 'подкинул'; }
      бито.click(); return 'бито';
    }
    const бросить = к('кнопка-бросить');
    if (бросить && !бросить.classList.contains('скрыт') && !бросить.disabled) { бросить.click(); return 'бросил'; }
    if (можно.length) { можно[0].click(); return 'сходил'; }
    return '';
  });
}

/** Уйти с экрана «назад», как человек: видна «‹» — ею, нет — стрелкой Telegram. */
async function назад(страница, примета) {
  const видна = await страница.evaluate((п) => { const к = document.querySelector(п); return Boolean(к && к.offsetParent !== null); }, примета);
  if (видна) await страница.click(примета);
  else await страница.evaluate(() => window.ПоддельныйТелеграм.нажатьНазад());
  await страница.waitForTimeout(400);
  return видна ? 'кнопкой на экране' : 'стрелкой Telegram';
}

