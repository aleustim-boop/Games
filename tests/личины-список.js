/* =====================================================================
   СПИСОК ЛИЧИН (server/личины.js): 80 записей, порядок старых не меняется,
   фото на месте. Без браузера и без сети.
   Проверяем:
     1) в списке ровно 80 личин; номера идут подряд от БАЗА_НОМЕРА + 1;
     2) имена не повторяются;
     3) первые 40 (имя и сила) совпадают с эталоном ниже — это страж
        «порядок старых личин не менять»: от номера зависят рейтинг, сила
        и фото личины, перестановка сделает «Андрея» другим человеком;
     4) фото: ровно 48, без повторов, имена вида фото-NN.webp (NN от 01 до 48);
     5) у каждой личины с фото файл ЕСТЬ в img/личины/, это webp (подпись
        RIFF….WEBP), не больше 64 КБ. Нет файла = провал (пока Кодекс не
        дорисовал, на настоящем проекте этот пункт может краснеть — это ожидаемо);
     6) svg в списке не осталось; типФото('x.webp') = image/webp.
   Запуск:  node tests/личины-список.js
   Довод для ломающих запусков:  --корень=<папка с копией server/личины.js и img/личины/>
   (портится КОПИЯ во временной папке, файлы проекта не трогаем).
   ===================================================================== */

const fs = require('fs');
const path = require('path');

const аргументКорня = process.argv.find(function (а) { return а.indexOf('--корень=') === 0; });
const КОРЕНЬ = аргументКорня ? path.resolve(аргументКорня.slice('--корень='.length)) : path.join(__dirname, '..');
const ФАЙЛ_ЛИЧИН = path.join(КОРЕНЬ, 'server', 'личины.js');
const ПАПКА_ФОТО = path.join(КОРЕНЬ, 'img', 'личины');

const ВСЕГО = 80;
const СТАРЫХ = 40;
const ФОТО_ВСЕГО = 48;
const ПРЕДЕЛ_БАЙТ = 64 * 1024;

/* Эталон первых 40 личин (имя, сила) — снят с server/личины.js коммита 1821c7f до расширения. */
