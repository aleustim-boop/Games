let проверок = 0;
let провалов = 0;
function проверить(условие, что) {
  проверок++;
  if (!условие) { провалов++; console.log('  ПРОВАЛ: ' + что); }
}

let личины = null;
try { личины = require(ФАЙЛ_ЛИЧИН); } catch (ошибка) {
  console.log('  ПРОВАЛ: не удалось загрузить ' + ФАЙЛ_ЛИЧИН + ': ' + ошибка.message);
  console.log('Итого проверок: 1, провалов: 1');
  process.exit(1);
}
const все = личины.все();

console.log('1. Размер и номера');
проверить(все.length === ВСЕГО, 'в списке ' + все.length + ' личин, нужно ' + ВСЕГО);
for (let i = 0; i < все.length; i++) {
  if (все[i].номер !== личины.БАЗА_НОМЕРА + i + 1) {
    проверить(false, 'номер личины №' + (i + 1) + ' (' + все[i].имя + ') — ' + все[i].номер + ', а должен идти подряд: ' + (личины.БАЗА_НОМЕРА + i + 1));
    break;
  }
}
проверить(все.length > 0, 'список личин пуст');

console.log('2. Имена');
{
  const видели = new Map();
  for (const л of все) {
    if (видели.has(л.имя)) проверить(false, 'имя «' + л.имя + '» повторяется (номера ' + видели.get(л.имя) + ' и ' + л.номер + ')');
    else видели.set(л.имя, л.номер);
  }
  проверить(все.every(function (л) { return typeof л.имя === 'string' && л.имя.trim() !== ''; }), 'есть личина без имени');
}

console.log('3. Первые 40 не тронуты');
проверить(ЭТАЛОН_СТАРЫХ.length === СТАРЫХ, 'в самой проверке эталон не из ' + СТАРЫХ + ' записей');
for (let i = 0; i < СТАРЫХ; i++) {
  const л = все[i];
  const эт = ЭТАЛОН_СТАРЫХ[i];
  if (!л || л.имя !== эт[0] || л.сила !== эт[1]) {
    проверить(false, 'личина №' + (i + 1) + ': было «' + эт[0] + '» (' + эт[1] + '), стало «' + (л && л.имя) + '» (' + (л && л.сила) + ')');
  }
}

console.log('4. Названия фото');
const сФото = все.filter(function (л) { return л.фото; });
проверить(сФото.length === ФОТО_ВСЕГО, 'личин с фото ' + сФото.length + ', нужно ' + ФОТО_ВСЕГО);
{
  const имена = сФото.map(function (л) { return л.фото; });
  проверить(new Set(имена).size === имена.length, 'одно фото назначено двум личинам');
  const плохие = имена.filter(function (и) {
    const м = /^фото-([0-9][0-9])\.webp$/.exec(и);
    return !м || Number(м[1]) < 1 || Number(м[1]) > ФОТО_ВСЕГО;
  });
  проверить(плохие.length === 0, 'имена фото не вида фото-NN.webp (01–48): ' + плохие.join(', '));
  const ждали = new Set();
  for (let i = 1; i <= ФОТО_ВСЕГО; i++) ждали.add('фото-' + (i < 10 ? '0' : '') + i + '.webp');
  const нет = Array.from(ждали).filter(function (и) { return !имена.includes(и); });
  проверить(нет.length === 0, 'в списке нет фото: ' + нет.join(', '));
  проверить(!все.some(function (л) { return л.фото && /\.svg$/i.test(л.фото); }), 'в списке остались фото в формате svg');
}

console.log('5. Файлы фото на диске');
{
  const нетФайла = [];
  const плохаяПодпись = [];
  const тяжёлые = [];
  for (const л of сФото) {
    const путь = path.join(ПАПКА_ФОТО, л.фото);
    if (!fs.existsSync(путь)) { нетФайла.push(л.фото); continue; }
    const байты = fs.readFileSync(путь);
    if (байты.length < 12 || байты.slice(0, 4).toString('latin1') !== 'RIFF' || байты.slice(8, 12).toString('latin1') !== 'WEBP') плохаяПодпись.push(л.фото);
    if (байты.length > ПРЕДЕЛ_БАЙТ) тяжёлые.push(л.фото + ' (' + Math.round(байты.length / 1024) + ' КБ)');
  }
  проверить(нетФайла.length === 0, 'нет файла фото (' + нетФайла.length + '): ' + нетФайла.join(', '));
  проверить(плохаяПодпись.length === 0, 'это не webp (нет подписи RIFF…WEBP): ' + плохаяПодпись.join(', '));
  проверить(тяжёлые.length === 0, 'тяжелее 64 КБ: ' + тяжёлые.join(', '));
  // Сам модуль должен отдавать фото тех личин, у кого файл есть, с типом webp.
  const отданные = сФото.filter(function (л) { return fs.existsSync(path.join(ПАПКА_ФОТО, л.фото)); });
  проверить(отданные.every(function (л) { const ф = личины.фото(л.номер); return ф && ф.тип === 'image/webp' && ф.байты.length > 0; }),
    'модуль не отдаёт фото личины с типом image/webp, хотя файл на диске есть');
}

console.log('6. Тип фото');
{
  // типФото не выставлена наружу — вырезаем функцию из исходника той же копии и выполняем отдельно.
  const исходник = fs.readFileSync(ФАЙЛ_ЛИЧИН, 'utf8');
  const начало = исходник.indexOf('function типФото(');
  const конец = исходник.indexOf('\n}', начало);
  const м = (начало >= 0 && конец > начало) ? [исходник.slice(начало, конец + 2)] : null;
  проверить(!!м, 'в server/личины.js не найдена функция типФото (переименована? проверка бессильна)');
  if (м) {
    const тип = new Function(м[0] + '; return типФото;')();
    проверить(тип('x.webp') === 'image/webp', "типФото('x.webp') = " + тип('x.webp') + ', нужно image/webp');
    проверить(тип('X.WEBP') === 'image/webp', 'типФото не понимает заглавные буквы .WEBP');
  }
}

console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
