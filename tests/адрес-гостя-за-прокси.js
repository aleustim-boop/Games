// Функция для загрузки модуля из другого места
function загрузитьМодульИз(путьКМодулю) {
  // Определяем папку проекта - два уровня выше от server/сервер.js
  const папкаСервера = path.dirname(путьКМодулю);
  const папкаПроекта = path.dirname(папкаСервера);

  // Очищаем кэш для всех модулей из папки server и js
  Object.keys(require.cache).forEach(ключ => {
    if (ключ.includes(path.sep + 'server' + path.sep) ||
        ключ.includes(path.sep + 'js' + path.sep) ||
        ключ.endsWith('сервер.js')) {
      delete require.cache[ключ];
    }
  });

  // Используем абсолютный путь - require найдёт модуль по полному пути
  const абсолютныйПуть = path.resolve(папкаПроекта, 'server', 'сервер.js');
  const м = require(абсолютныйПуть);
  return м;
}

