/* =====================================================================
   УСКОРИТЕЛЬ ПАУЗ — чтобы за час успеть сыграть не три партии, а тридцать.

   Зачем. Бот нарочно думает 0,7 секунды перед каждым ходом, а сообщения
   на столе висят ещё дольше — так человеку видно, что произошло. Партия
   из-за этого идёт три-четыре минуты, и проверить полтора десятка партий
   подряд (а серия побед иначе не проверяется) — это целый вечер ожидания.

   Что делает. Укорачивает ДЛИННЫЕ паузы игры: всё, что игра просит ждать
   дольше 0,4 секунды, ждётся в шесть раз быстрее. Короткие паузы (шаг
   автоигрока — 0,22 с) не трогаются вовсе: иначе «палец» начал бы нажимать
   чаще, чем игра успевает слышать руку, и мы записали бы несуществующую
   поломку.

   Чего он НЕ делает. Не меняет ни правил, ни карт, ни решений бота —
   только скорость показа. Всё, что найдено с ускорителем, обязательно
   перепроверяется в обычном темпе: в отчёте это отмечается отдельно.

   Как пользоваться (из консоли браузера, до начала партии):
       УскорительПауз.включить();     // дальше играем быстро
       УскорительПауз.выключить();    // вернуть обычный темп
   ===================================================================== */

(function () {
  'use strict';

  const ПОРОГ = 400;      // паузы короче этой (мс) не трогаем совсем
  const ВО_СКОЛЬКО = 6;   // во столько раз укорачиваем длинные паузы
  const МИНИМУМ = 60;     // но не короче этого, чтобы не слиплись подряд идущие шаги

  const родной = window.setTimeout;
  let включён = false;

  window.УскорительПауз = {
    включить: function () {
      if (включён) return 'уже ускорено';
      window.setTimeout = function (что, сколько) {
        const пауза = typeof сколько === 'number' && сколько >= ПОРОГ
          ? Math.max(МИНИМУМ, Math.round(сколько / ВО_СКОЛЬКО))
          : сколько;
        const остальное = [].slice.call(arguments, 2);
        return родной.apply(window, [что, пауза].concat(остальное));
      };
      включён = true;
      return 'паузы длиннее ' + ПОРОГ + ' мс укорочены в ' + ВО_СКОЛЬКО + ' раз';
    },
    выключить: function () {
      window.setTimeout = родной;
      включён = false;
      return 'обычный темп вернулся';
    },
    включён: function () { return включён; }
  };
})();
