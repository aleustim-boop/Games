async function прогонСостояния(браузер, состояние, ширина, адрес, снимки) {
  const метка = состояние.имя;
  let контекст = null;
  try {
    const открытое = await открытьСтраницу(браузер, ширина, состояние, адрес);
    контекст = открытое.контекст;
    const страница = открытое.страница;
    const красные = открытое.красные;

    const витринаОткрылась = await страница.waitForSelector('#экран-витрины.экран--виден', { timeout: ТАЙМАУТ_ДЕЙСТВИЯ }).catch(() => null);
    if (!проверить(метка, ширина, 'стартовый экран «витрина» открылся', Boolean(витринаОткрылась))) {
      записатьНаходки(метка, ширина, 'ошибки в консоли', красные);
      return;
    }

    if (состояние.переходВЛобби !== false) {
      if (!await действиеЛобби(страница, метка, ширина)) {
        записатьНаходки(метка, ширина, 'ошибки в консоли', красные);
        return;
      }
    }

    if (состояние.действие) {
      const действиеУдалось = await состояние.действие(страница, метка, ширина);
      if (!действиеУдалось) {
        записатьНаходки(метка, ширина, 'ошибки в консоли', красные);
        return;
      }
    }

    await дождатьсяУстойчивойРаскладки(страница);
    const замеры = await собратьЗамеры(страница);
    записатьНаходки(метка, ширина, 'пересекаются интерактивные элементы', замеры.пересечения);
    записатьНаходки(метка, ширина, 'обрезанный текст без многоточия', замеры.обрезанные);
    записатьНаходки(метка, ширина, 'зазор меньше 8px между кнопками', замеры.тесныЗазоры);
    записатьНаходки(метка, ширина, 'элемент вылезает за край экрана', замеры.заЭкраном);
    проверить(метка, ширина, 'нет горизонтальной прокрутки страницы', !замеры.прокруткаЕсть, замеры.прокруткаДеталь);
    записатьНаходки(метка, ширина, 'ошибки в консоли', красные);

    const путьСнимка = path.join(ПАПКА_СНИМКОВ, метка + '-' + ширина + '.png');
    const буфер = await страница.screenshot();
    fs.writeFileSync(путьСнимка, буфер);
    const хэш = crypto.createHash('sha1').update(буфер).digest('hex');
    снимки.push({ имя: метка, ширина: ширина, хэш: хэш, путь: путьСнимка });
  } catch (ошибка) {
    проверок++; провалов++;
    const строка = 'ПЛОХО — ' + метка + ' ' + ширина + ': проверка упала — ' + (ошибка && ошибка.message || ошибка);
    console.log(строка);
    находки.push(строка);
  } finally {
    if (контекст) await контекст.close().catch(() => null);
  }
}

/* ---------------------------------------------------------------------
   ДОПОЛНИТЕЛЬНЫЙ ОБХОД: витрина на настоящих размерах устройств + режим
   Telegram — см. «ДОБАВКА 23.09» в шапке файла.
   --------------------------------------------------------------------- */

/** Собрать замеры витрины: цепочка предков (overflow-y/height/padding-bottom —
 *  для отчёта, что именно мешает прокрутке, если мешает), общая способность
 *  контейнера прокрутиться до конца, и по каждой из 8 плиток — видна ли
 *  она ЦЕЛИКОМ после того, как её докрутили к низу окна.
 *
 *  ВАЖНО про «докрутили к низу окна» — почему не «один раз scrollTop =
 *  scrollHeight и смотрим на всё сразу». На высоком телефоне/планшете
 *  ряды плиток (нарды/шахматы, дурак/шашки, домино/морской-бой,
 *  катан, деберц) в сумме ВЫШЕ окна почти всегда — это не баг, это нормальная
 *  прокручиваемая витрина, а не баг. Первая версия этой проверки требовала
 *  одновременной видимости ВСЕХ 8 плиток после ОДНОЙ прокрутки в самый
 *  конец — и на 768×1024 честно проваливалась на «нарды»/«шахматы»
 *  (первый ряд, ушёл ЗА ВЕРХ экрана, потому что от их положения до конца
 *  контента дальше, чем высота окна) — то есть путала «человек долистал
 *  дальше и верхний ряд по-честному уехал вверх» с настоящей бедой
 *  владельца («нижняя плитка спрятана под панелью, ниже докрутить
 *  нельзя»). Правильная проверка — для КАЖДОЙ плитки СВОЯ прокрутка:
 *  «плитка.scrollIntoView({ block: 'end' })» подводит именно ЕЁ нижний
 *  край к низу видимой области — тем же приёмом, что уже проверен в этом
 *  файле для пересечений с нижней полосой (см. «а, продолжение» в
 *  собратьЗамеры выше). Так каждая плитка проверяется в СВОЁМ самом
 *  тесном по вертикали положении, а не в положении соседней плитки. */
async function собратьЗамерыВитрины(страница) {
  return страница.evaluate(async () => {
    function кадр() { return new Promise((г) => requestAnimationFrame(() => requestAnimationFrame(г))); }
    function путьДо(эл) {
      if (!эл) return 'ничего (точка за пределами окна)';
      if (эл.id) return '#' + эл.id;
      const кл = (эл.className && typeof эл.className === 'string') ? эл.className.trim().split(/\s+/)[0] : '';
      return эл.tagName.toLowerCase() + (кл ? '.' + кл : '');
    }

    const контейнер = document.querySelector('#экран-витрины.витрина');
    if (!контейнер) return { контейнерНайден: false };

    // Цепочка предков от контейнера до <html> — overflow-y/height/padding-bottom
    // КАЖДОГО, штабу для диагностики, что именно мешает прокрутке (если мешает).
    const предки = [];
    for (let узел = контейнер; узел; узел = узел.parentElement) {
      const с = getComputedStyle(узел);
      предки.push({
        путь: узел === document.documentElement ? 'html' : путьДо(узел),
        overflowY: с.overflowY, height: с.height, maxHeight: с.maxHeight, paddingBottom: с.paddingBottom
      });
    }

    const плитки = Array.prototype.slice.call(document.querySelectorAll('.плитка-игры'));

    // Общая способность контейнера прокрутиться до конца — грубая проверка
    // «прокрутка вообще не заблокирована», не про одновременную видимость.
    const scrollHeightДо = контейнер.scrollHeight;
    const clientHeight = контейнер.clientHeight;
    const scrollTopДо = контейнер.scrollTop;
    контейнер.scrollTop = контейнер.scrollHeight;
    await кадр();
    const scrollTopПосле = контейнер.scrollTop;
    контейнер.scrollTop = scrollTopДо; // вернуть на место перед покадровой проверкой плиток

    const результатыПлиток = [];
    for (const плитка of плитки) {
      const имя = плитка.getAttribute('data-игра') || путьДо(плитка);
      try { плитка.scrollIntoView({ block: 'end' }); } catch (о) { /* нечем прокрутить — считаем как есть */ }
      await кадр();
      await кадр();
      const r = плитка.getBoundingClientRect();
      if (r.width <= 0 || r.height <= 0) {
        результатыПлиток.push({ имя: имя, видна: false, провалы: ['плитка нулевого размера (width=' + r.width + ', height=' + r.height + ')'] });
        continue;
      }
      const точки = [
        ['левый-верхний',  r.left + 4,           r.top + 4],
        ['правый-верхний', r.right - 4,          r.top + 4],
        ['левый-нижний',   r.left + 4,           r.bottom - 4],
        ['правый-нижний',  r.right - 4,          r.bottom - 4],
        ['центр',          r.left + r.width / 2, r.top + r.height / 2]
      ];
      const провалы = [];
      точки.forEach(function (т) {
        const имяТочки = т[0], x = т[1], y = т[2];
        let верхний = null;
        if (x >= 0 && y >= 0 && x <= window.innerWidth && y <= window.innerHeight) {
          верхний = document.elementFromPoint(x, y);
        }
        const ок = верхний && (верхний === плитка || плитка.contains(верхний) || верхний.contains(плитка));
        if (!ок) {
          провалы.push(имяТочки + ': там «' + путьДо(верхний) + '» вместо плитки (' + Math.round(x) + ',' + Math.round(y) +
            ', окно ' + window.innerWidth + '×' + window.innerHeight + ')');
        }
      });
      результатыПлиток.push({
        имя: имя, видна: провалы.length === 0, провалы: провалы,
        rect: { top: Math.round(r.top), bottom: Math.round(r.bottom), left: Math.round(r.left), right: Math.round(r.right) }
      });
    }

    return {
      контейнерНайден: true, предки: предки, всегоПлиток: плитки.length,
      scrollTopДо: scrollTopДо, scrollHeightДо: scrollHeightДо, clientHeight: clientHeight,
      scrollTopПосле: scrollTopПосле, плитки: результатыПлиток
    };
  });
}

/** Один прогон витрины: настоящий размер устройства × режим (браузер/Telegram). */
async function прогонВитриныНаРазмере(браузер, размер, вТелеграме, адрес) {
  const метка = 'витрина ' + размер.ширина + '×' + размер.высота + (вТелеграме ? ' в Telegram' : ' в браузере');
  const подпись = '(' + размер.имя + ')';
  let контекст = null;
  try {
    контекст = await браузер.newContext({ viewport: { width: размер.ширина, height: размер.высота }, hasTouch: true });
    const страница = await контекст.newPage();

    const красные = [];
    страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
    страница.on('console', (м) => {
      if (м.type() !== 'error') return;
      const т = м.text();
      const откуда = (м.location() && м.location().url) || '';
      if (/telegram-web-app\.js|telegram\.org/.test(т) || /telegram-web-app\.js|telegram\.org/.test(откуда)) return;
      красные.push('консоль: ' + т);
    });

    if (вТелеграме) {
      await подготовитьПодделку(страница, { версия: '8.0', отступы: ОТСТУПЫ_ТЕЛЕГРАМА });
    } else {
      await безTelegram(страница); // обычный браузер: никакого Telegram вовсе, класса «в-телеграме» не будет
    }

    // Дверь /рейтинг на витрине не спрашивают, но перехват не мешает и снимает риск,
    // если какой-то будущий код витрины вдруг тоже её спросит.
    await перехватить(страница, new RegExp('/рейтинг(?:\\?|$)'), function (путь) {
      путь.fulfill({ status: 200, contentType: 'application/json; charset=utf-8', body: JSON.stringify(ответНовичок('дурак')) });
    });

    await страница.goto(адрес + '/index.html');
    const витринаОткрылась = await страница.waitForSelector('#экран-витрины.экран--виден', { timeout: ТАЙМАУТ_ДЕЙСТВИЯ }).catch(() => null);
    if (!проверить(метка, подпись, 'стартовый экран «витрина» открылся', Boolean(витринаОткрылась))) {
      записатьНаходки(метка, подпись, 'ошибки в консоли', красные);
      return;
    }
    await дождатьсяУстойчивойРаскладки(страница);

    // Два снимка на весь прогон — только 768×1024 в Telegram, ближайший
    // к жалобе владельца размер из тех, что уже входят в опись задания.
    const делатьСнимки = размер.ширина === 768 && размер.высота === 1024 && вТелеграме;
    if (делатьСнимки) {
      fs.writeFileSync(path.join(ПАПКА_СНИМКОВ, 'витрина-768x1024-телеграм-1-до-прокрутки.png'), await страница.screenshot());
    }

    const замеры = await собратьЗамерыВитрины(страница);

    if (!проверить(метка, подпись, 'контейнер «#экран-витрины.витрина» найден', Boolean(замеры.контейнерНайден))) {
      записатьНаходки(метка, подпись, 'ошибки в консоли', красные);
      return;
    }

    // «Ноль найденного — провал, а не пропуск» (правило штаба): плиток должно быть ровно 8
    // (24.09: на витрине появилась 8-я игра — Катан, число проверки поднято тестировщиком вместе с этим фактом).
    проверить(метка, подпись, 'на витрине найдены все 8 плиток (нашлось ' + замеры.всегоПлиток + ')',
      замеры.всегоПлиток === 8,
      замеры.всегоПлиток === 0 ? 'селектор «.плитка-игры» не нашёл НИ ОДНОЙ плитки — переименовали класс?' : undefined);

    // Возможность прокрутки — только если контента реально больше, чем видно.
    const контентВышеОкна = замеры.scrollHeightДо > замеры.clientHeight + 1;
    if (контентВышеОкна) {
      const скрытыеПредки = (замеры.предки || [])
        .filter((п) => п.overflowY === 'hidden' && п.путь !== 'html' && п.путь !== 'body'); // html и body скрыты нарочно (style.css:256) — сама витрина прокручивается сама в себе, не через html/body
      записатьНаходки(метка, подпись, 'overflow-y:hidden у предка контейнера — мог бы мешать прокрутке',
        скрытыеПредки.map((п) => п.путь + ' (overflow-y=hidden, height=' + п.height + ', padding-bottom=' + п.paddingBottom + ')'));
      проверить(метка, подпись, 'прокрутка вниз реально сработала (scrollTop сдвинулся к концу)',
        замеры.scrollTopПосле > замеры.scrollTopДо + 1,
        'до: ' + замеры.scrollTopДо + ', после: ' + замеры.scrollTopПосле + ', нужно бы: ' + (замеры.scrollHeightДо - замеры.clientHeight) +
        ' (scrollHeight=' + замеры.scrollHeightДо + ', clientHeight=' + замеры.clientHeight + ')');
    } else {
      проверок++;
      console.log('  ок    — ' + метка + ' ' + подпись + ': контент помещается без прокрутки (scrollHeight=' +
        замеры.scrollHeightДо + ' ≤ clientHeight=' + замеры.clientHeight + ')');
    }

    // Каждая из 8 плиток обязана быть ЦЕЛИКОМ видна после прокрутки до конца.
    const плохиеПлитки = (замеры.плитки || []).filter((п) => !п.видна);
    записатьНаходки(метка, подпись, 'плитка не видна целиком после прокрутки до конца (закрыта чем-то или уехала за экран)',
      плохиеПлитки.map((п) => '«' + п.имя + '» ' + JSON.stringify(п.rect) + ': ' + п.провалы.join('; ')));

    записатьНаходки(метка, подпись, 'ошибки в консоли', красные);

    if (делатьСнимки) {
      fs.writeFileSync(path.join(ПАПКА_СНИМКОВ, 'витрина-768x1024-телеграм-2-после-прокрутки.png'), await страница.screenshot());
    }

    if (плохиеПлитки.length || (контентВышеОкна && замеры.scrollTopПосле <= замеры.scrollTopДо + 1)) {
      КРАСНЫЕ_РАЗМЕРЫ_ВИТРИНЫ.push(метка + ' ' + подпись);
    }
  } catch (ошибка) {
    проверок++; провалов++;
    const строка = 'ПЛОХО — ' + метка + ' ' + подпись + ': проверка упала — ' + (ошибка && ошибка.message || ошибка);
    console.log(строка);
    находки.push(строка);
  } finally {
    if (контекст) await контекст.close().catch(() => null);
  }
}

/* ---------------------------------------------------------------------
   Приоритетная проверка: два РАЗНЫХ состояния с одинаковым снимком (той
   же ширины) — ПЛОХО, а не «ну, просто похожие».
   --------------------------------------------------------------------- */

function проверитьОдинаковыеСнимки(снимки) {
  console.log('\n=== Приоритетная проверка: одинаковые снимки РАЗНЫХ состояний ===');
  let нашлиСовпадение = false;
  for (const ширина of ШИРИНЫ) {
    const наШирине = снимки.filter((с) => с.ширина === ширина);
    for (let i = 0; i < наШирине.length; i++) {
      for (let j = i + 1; j < наШирине.length; j++) {
        const a = наШирине[i], b = наШирине[j];
        проверок++;
        if (a.хэш === b.хэш) {
          нашлиСовпадение = true;
          провалов++;
          const строка = 'ПЛОХО — совпадение снимков на ширине ' + ширина + ': «' + a.имя + '» и «' + b.имя +
            '» — байт в байт одинаковые (хэш ' + a.хэш.slice(0, 12) + '…, файлы ' + path.basename(a.путь) + ' / ' + path.basename(b.путь) + ')';
          console.log(строка);
          находки.push(строка);
        } else {
          console.log('  ок    — ширина ' + ширина + ': «' + a.имя + '» ≠ «' + b.имя + '» (снимки разные)');
        }
      }
    }
  }
  if (!нашлиСовпадение) console.log('  ни одной пары совпавших снимков не нашлось — состояния визуально различаются.');
}

