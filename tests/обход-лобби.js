/* ---------------------------------------------------------------------
   Открыть страницу на СВОЁМ временном сервере, подделать Telegram и
   дверь /рейтинг, при нужде подменить имя игрока на длинное.
   --------------------------------------------------------------------- */

async function открытьСтраницу(браузер, ширина, состояние, адрес) {
  const viewport = { width: ширина, height: ширина < 700 ? 844 : 1000 };
  const контекст = await браузер.newContext({ viewport: viewport, hasTouch: ширина < 700 });
  const страница = await контекст.newPage();

  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const т = м.text();
    const откуда = (м.location() && м.location().url) || '';
    if (/telegram-web-app\.js|telegram\.org/.test(т) || /telegram-web-app\.js|telegram\.org/.test(откуда)) return;
    красные.push('консоль: ' + т);
  });
  страница.on('requestfailed', (з) => {
    const адресЗапроса = з.url();
    if (/telegram-web-app\.js|telegram\.org/.test(адресЗапроса)) return;
    красные.push('сеть: ' + адресЗапроса + ' — ' + (з.failure() && з.failure().errorText));
  });

  if (состояние.безTelegram) {
    // Лист «Ещё» на странице виден только ВНЕ Telegram — телеграм не
    // подделываем вовсе, только не пускаем настоящий скрипт telegram.org
    // (иначе он позже перетрёт наши ожидания сетевым запросом впустую).
    await безTelegram(страница);
  } else {
    await подготовитьПодделку(страница, { версия: '8.0' });

    // Имя жёстко закодировано в поддельном Telegram как «Проверяющий» —
    // для сценариев с длинным именем переопределяем его ВТОРЫМ addInitScript
    // (Playwright гарантирует, что они выполняются по порядку добавления,
    // а window.Telegram.WebApp к этому моменту уже создан первым скриптом).
    if (состояние.длинноеИмя) {
      await страница.addInitScript({
        content: '(function(){ if (window.Telegram && window.Telegram.WebApp && window.Telegram.WebApp.initDataUnsafe && window.Telegram.WebApp.initDataUnsafe.user) { window.Telegram.WebApp.initDataUnsafe.user.first_name = ' +
          JSON.stringify(ИМЯ_ДЛИННОЕ) + '; window.Telegram.WebApp.initDataUnsafe.user.last_name = \'\'; } })();'
      });
    }
  }

  // Дверь /рейтинг — её спрашивают и карточка профиля лобби, и вкладка «Профиль».
  await перехватить(страница, new RegExp('/рейтинг(?:\\?|$)'), function (путь, запрос) {
    let игра = 'дурак';
    try {
      const тело = JSON.parse((запрос.postData && запрос.postData()) || '{}');
      if (тело && тело.игра) игра = тело.игра;
    } catch (о) { /* тела может не быть */ }
    путь.fulfill({ status: 200, contentType: 'application/json; charset=utf-8', body: JSON.stringify(состояние.ответ(игра)) });
  });

  await страница.goto(адрес + '/index.html');
  await страница.waitForTimeout(600);

  return { контекст: контекст, страница: страница, красные: красные };
}

/* ---------------------------------------------------------------------
   Автоматический поиск поломок вида — одним page.evaluate (без изменений
   по сути от tests/обход-рейтинга.js, переписано на месте).
   --------------------------------------------------------------------- */

/** Ждать, пока раскладка страницы перестанет меняться между кадрами —
 *  шрифты, картинки, потом сравнение подряд идущих замеров координат
 *  (см. «ПРАВКА ПО ЗАМЕЧАНИЯМ ШТАБА» п.2 в шапке файла). Замер, снятый
 *  раньше времени, путает «ещё не устоялось» с «баг вида». */
async function дождатьсяУстойчивойРаскладки(страница) {
  await страница.evaluate(async () => {
    function снимок() {
      const части = [];
      Array.prototype.slice.call(document.querySelectorAll('button, a, span, img, li')).forEach(function (эл) {
        const r = эл.getBoundingClientRect();
        части.push(Math.round(r.left) + ',' + Math.round(r.top) + ',' + Math.round(r.width) + ',' + Math.round(r.height));
      });
      const приложение = document.getElementById('приложение');
      части.push('scroll:' + (приложение ? приложение.scrollWidth : 0));
      return части.join('|');
    }
    function кадр() {
      return new Promise((готово) => requestAnimationFrame(() => requestAnimationFrame(готово)));
    }
    try { if (document.fonts && document.fonts.ready) await document.fonts.ready; } catch (о) { /* нет шрифтов API — не критично */ }
    const картинки = Array.prototype.slice.call(document.images);
    await Promise.all(картинки.map((img) => img.complete ? Promise.resolve() :
      new Promise((готово) => { img.addEventListener('load', готово); img.addEventListener('error', готово); })));
    await кадр();
    let предыдущий = снимок();
    for (let попытка = 0; попытка < 12; попытка++) {
      await кадр();
      const текущий = снимок();
      if (текущий === предыдущий) return;
      предыдущий = текущий;
    }
    // за 12 кадров подряд раскладка не устоялась — дальше решает обычный замер,
    // сам этот факт мы не глушим и не считаем ошибкой сам по себе.
  });
}

async function собратьЗамеры(страница) {
  return страница.evaluate(async () => {
    function путьДо(эл) {
      if (эл.id) return '#' + эл.id;
      const кл = (эл.className && typeof эл.className === 'string') ? эл.className.trim().split(/\s+/)[0] : '';
      const текст = (эл.textContent || '').trim().slice(0, 24).replace(/\s+/g, ' ');
      return эл.tagName.toLowerCase() + (кл ? '.' + кл : '') + (текст ? ' «' + текст + '»' : '');
    }

    function видимЛи(эл, rect) {
      if (rect.width <= 0 || rect.height <= 0) return false;
      const с = getComputedStyle(эл);
      if (с.visibility === 'hidden' || с.display === 'none' || parseFloat(с.opacity) === 0) return false;
      return true;
    }

    /* Классический приём «только для программы чтения с экрана»: подпись
       занимает 1×1 точку и обрезана clip-path/clip до нуля, но НЕ
       display:none (иначе её пропустила бы и программа чтения). Так
       спрятаны названия/описания плиток витрины — фото уже показывает
       игру, а второй видимый подписи README запрещает (style.css:1435,
       «Только для чтения с экрана»). Это не обрезка, а нарочный приём —
       «обрезанный текст» его ловить не должен. */
    function толькоДляЧтенияЭкраном(эл, rect, с) {
      if (rect.width > 1 || rect.height > 1) return false;
      if (с.position !== 'absolute' && с.position !== 'fixed') return false;
      const клипPath = с.clipPath || '';
      const клип = с.clip || '';
      if (клипPath.indexOf('inset(50%)') !== -1 || клипPath.indexOf('inset(100%)') !== -1) return true;
      return /rect\(\s*0(px)?[, ]+0(px)?[, ]+0(px)?[, ]+0(px)?\s*\)/.test(клип);
    }

    /* Элемент участвует в сравнении на пересечения, только если он
       РЕАЛЬНО СВЕРХУ в своей же точке: document.elementFromPoint(центр)
       возвращает сам элемент или его потомка — иначе шторка/подложка,
       честно накрывшая его, ложно считалась бы «наездом». */
    function элементРеальноСверху(эл, rect) {
      const cx = rect.left + rect.width / 2;
      const cy = rect.top + rect.height / 2;
      if (cx < 0 || cy < 0 || cx > window.innerWidth || cy > window.innerHeight) return false;
      const верхний = document.elementFromPoint(cx, cy);
      if (!верхний) return false;
      return верхний === эл || эл.contains(верхний) || верхний.contains(эл);
    }

    function следующийКадр() {
      return new Promise((готово) => requestAnimationFrame(() => requestAnimationFrame(готово)));
    }

    const заметные = [];
    Array.prototype.slice.call(document.querySelectorAll('*')).forEach(function (эл) {
      if (эл.tagName === 'SCRIPT' || эл.tagName === 'STYLE' || эл.tagName === 'HEAD') return;
      const rect = эл.getBoundingClientRect();
      if (!видимЛи(эл, rect)) return;
      const прямойТекст = Array.prototype.slice.call(эл.childNodes)
        .some((n) => n.nodeType === 3 && n.textContent.trim().length > 0);
      заметные.push({ эл: эл, rect: rect, прямойТекст: прямойТекст });
    });

    // а) интерактивные элементы, видимые и не закрытые чужим сверху
    const интерактивныеТеги = { BUTTON: 1, A: 1, INPUT: 1, SELECT: 1, TEXTAREA: 1 };
    const интерактивные = [];
    заметные.forEach(function (з) {
      const эл = з.эл;
      const интерактивен = интерактивныеТеги[эл.tagName] || эл.getAttribute('role') === 'button';
      if (!интерактивен) return;
      if (!элементРеальноСверху(эл, з.rect)) return;
      интерактивные.push({
        эл: эл, путь: путьДо(эл), tag: эл.tagName.toLowerCase(),
        top: з.rect.top, bottom: з.rect.bottom, left: з.rect.left, right: з.rect.right
      });
    });

    // Кандидаты на пересечение — по уже устоявшейся (см. дождатьсяУстойчивойРаскладки) раскладке.
    const кандидатыПересечений = [];
    for (let i = 0; i < интерактивные.length; i++) {
      for (let j = i + 1; j < интерактивные.length; j++) {
        const a = интерактивные[i], b = интерактивные[j];
        const пересекаются = a.left < b.right && b.left < a.right && a.top < b.bottom && b.top < a.bottom;
        if (!пересекаются) continue;
        const aВнутриB = b.left <= a.left && b.right >= a.right && b.top <= a.top && b.bottom >= a.bottom;
        const bВнутриA = a.left <= b.left && a.right >= b.right && a.top <= b.top && a.bottom >= b.bottom;
        if (aВнутриB || bВнутриA) continue;
        кандидатыПересечений.push([a, b]);
      }
    }

    // д) тесный зазор между кнопками (button/a), стоящими друг под другом.
    const кнопки = интерактивные.filter((э) => э.tag === 'button' || э.tag === 'a');
    const тесныЗазоры = [];
    for (let i = 0; i < кнопки.length; i++) {
      for (let j = 0; j < кнопки.length; j++) {
        if (i === j) continue;
        const a = кнопки[i], b = кнопки[j];
        const overlapX = Math.min(a.right, b.right) - Math.max(a.left, b.left);
        if (overlapX <= 0) continue;
        if (b.top < a.bottom) continue;
        const gap = b.top - a.bottom;
        const одинРодитель = Boolean(a.эл.parentElement) && a.эл.parentElement === b.эл.parentElement;
        if (одинРодитель) {
          /* Соседние строки ОДНОГО родителя, каждая шириной с него (список
             очков в профиле и подобные) — зазором не меряем вовсе: между
             двумя строками во всю ширину нет «дыры», в которую может
             соскользнуть палец. Признак — по форме (ширина строки против
             ширины родителя), не по имени класса. */
          const ширинаРодителя = a.эл.parentElement.getBoundingClientRect().width;
          const aВоВсюШирину = ширинаРодителя > 0 && (a.right - a.left) >= ширинаРодителя - 2;
          const bВоВсюШирину = ширинаРодителя > 0 && (b.right - b.left) >= ширинаРодителя - 2;
          if (aВоВсюШирину && bВоВсюШирину) continue;
        }
        const порог = одинРодитель ? 4 : 8;
        if (gap >= 0 && gap < порог) {
          тесныЗазоры.push(a.путь + ' — ' + b.путь + ' (зазор ' + Math.round(gap) + 'px, порог ' + порог + 'px' +
            (одинРодитель ? ', один список' : '') + ')');
        }
      }
    }

    // б) обрезанный текст без многоточия — кроме нарочных подписей
    // «только для чтения с экрана» (толькоДляЧтенияЭкраном выше).
    const обрезанные = [];
    заметные.forEach(function (з) {
      if (!з.прямойТекст) return;
      const эл = з.эл;
      const разница = эл.scrollWidth - эл.clientWidth;
      if (разница <= 2) return;
      const с = getComputedStyle(эл);
      if (с.textOverflow === 'ellipsis') return;
      if (толькоДляЧтенияЭкраном(эл, з.rect, с)) return;
      обрезанные.push(путьДо(эл) + ' (scrollWidth=' + эл.scrollWidth + ', clientWidth=' + эл.clientWidth + ')');
    });

    // в) горизонтальная прокрутка страницы — мерим #приложение (position:fixed,
    // переполнение внутри него не видно у html/body).
    const приложение = document.getElementById('приложение');
    const scrollWidthПриложения = приложение ? приложение.scrollWidth : document.documentElement.scrollWidth;
    const scrollWidth = Math.max(document.documentElement.scrollWidth, document.body ? document.body.scrollWidth : 0, scrollWidthПриложения);
    const clientWidth = window.innerWidth;
    const прокруткаЕсть = scrollWidth > clientWidth + 1;

    // г) элементы за краем экрана
    const заЭкраном = [];
    заметные.forEach(function (з) {
      if (з.rect.left < -1 || з.rect.right > window.innerWidth + 1) {
        заЭкраном.push(путьДо(з.эл) + ' (left=' + Math.round(з.rect.left) + ', right=' + Math.round(з.rect.right) +
          ', ширина окна=' + window.innerWidth + ')');
      }
    });

    /* а, продолжение: наезд на ЗАКРЕПЛЁННУЮ (fixed) нижнюю полосу вкладок
       засчитываем, только если он остаётся ПОСЛЕ прокрутки экрана до
       конца — пока страница не докручена, обычный (не закреплённый)
       элемент внизу может по координатам временно совпасть с полосой;
       докрутить — и между ними честный отступ. Пары без участия полосы
       вкладок прокрутки не ждут: там наезд от скролла не зависит,
       докручивать нечего.
       НАХОДКА 23.09 (второй заход, десятый провал профиля с длинным
       именем): раньше докручивали через страничный.эл.scrollIntoView
       ({block:'end'}) — родной API браузера НЕ сдвигает контейнер, если
       элемент и так укладывается в clientHeight целиком, хотя видимую
       часть внизу закрывает ЗАКРЕПЛЁННАЯ полоса вкладок — «видимость»
       по мнению scrollIntoView не совпадает с настоящей видимостью на
       экране (полоса рисуется ПОВЕРХ, а не сдвигает clientHeight).
       Проверено вручную (замер-профиля.js): на 320/390 у экрана профиля
       был запас прокрутки 23–26px, которого хватало, чтобы кнопка
       «Как я играю» ушла выше полосы — но scrollIntoView его не
       использовал, и провал оказывался ложным. Чиним докруткой самого
       прокручиваемого предка «до упора» (scrollTop = scrollHeight) —
       так же, как палец пользователя листает экран до конца. */
    const активныйЭкран = document.querySelector('.экран--виден') || document.getElementById('приложение');
    const исходныйScrollTop = активныйЭкран ? активныйЭкран.scrollTop : 0;
    const пересечения = [];
    for (const пара of кандидатыПересечений) {
      const a = пара[0], b = пара[1];
      const aВПолосе = Boolean(a.эл.closest && a.эл.closest('.нижние-вкладки'));
      const bВПолосе = Boolean(b.эл.closest && b.эл.closest('.нижние-вкладки'));
      if (aВПолосе !== bВПолосе) {
        try { if (активныйЭкран) активныйЭкран.scrollTop = активныйЭкран.scrollHeight; } catch (о) { /* нечем прокрутить — считаем как есть */ }
        await следующийКадр();
        const rA = a.эл.getBoundingClientRect(), rB = b.эл.getBoundingClientRect();
        if (!(rA.left < rB.right && rB.left < rA.right && rA.top < rB.bottom && rB.top < rA.bottom)) continue; // докрутили — уже не пересекаются
      }
      пересечения.push(a.путь + ' × ' + b.путь);
    }
    if (активныйЭкран) активныйЭкран.scrollTop = исходныйScrollTop;

    return {
      пересечения: пересечения, тесныЗазоры: тесныЗазоры, обрезанные: обрезанные,
      прокруткаЕсть: прокруткаЕсть,
      прокруткаДеталь: 'scrollWidth #приложение=' + scrollWidthПриложения + ', innerWidth=' + clientWidth,
      заЭкраном: заЭкраном, всегоИнтерактивных: интерактивные.length
    };
  });
}

