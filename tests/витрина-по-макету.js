/** Простой разбор разметки тела страницы: теги, атрибуты в двойных кавычках, текст. */
function собратьРазметку(html, документ) {
  const чистый = html.replace(/<!--[\s\S]*?-->/g, '').replace(/<script[\s\S]*?<\/script>/g, '');
  const тело = /<body[^>]*>([\s\S]*)<\/body>/.exec(чистый)[1];
  const образец = /<(\/?)([a-zA-Z][\w-]*)([^>]*?)(\/?)>|([^<]+)/g;
  const ПУСТЫЕ = new Set(['input', 'br', 'img', 'meta', 'link', 'hr']);
  const стек = [документ.body];
  let м;
  while ((м = образец.exec(тело))) {
    if (м[5] !== undefined) {
      if (м[5].trim()) стек[стек.length - 1].appendChild(документ.createTextNode(м[5]));
      continue;
    }
    const тег = м[2].toLowerCase();
    if (м[1] === '/') {
      for (let i = стек.length - 1; i > 0; i--) if (стек[i].tagName === тег.toUpperCase()) { стек.length = i; break; }
      continue;
    }
    const узел = документ.createElement(тег);
    const атр = /([^\s=]+)(?:\s*=\s*"([^"]*)")?/g;
    let а;
    while ((а = атр.exec(м[3]))) {
      узел.setAttribute(а[1], а[2] === undefined ? '' : а[2]);
      if (а[1] === 'disabled') узел.disabled = true;
    }
    стек[стек.length - 1].appendChild(узел);
    if (м[4] !== '/' && !ПУСТЫЕ.has(тег)) стек.push(узел);
  }
}

/*
 * В настоящем браузере `nav.innerHTML = '<button>…</button>'` тут же строит
 * настоящие узлы с id, атрибутами и обработчиками. Поддельный документ
 * (tests/поддельный-браузер.js) HTML внутри innerHTML нарочно не
 * разбирает — держит как текст, «чтобы не потерять» (так у него написано
 * в комментарии к innerHTML), а сам сеттер innerHTML у узла — свойство
 * без configurable, снаружи его не подменить (Object.defineProperty на
 * такое бросает исключение). Трогать сам поддельный браузер нельзя — это
 * общий файл ещё дюжины проверок.
 *
 * Поэтому вместо своего обработчика (это была вторая копия: сломай
 * настоящую привязку в js/нижние-вкладки.js — проверка не заметит, ловит
 * свою же копию) подменяем не сеттер, а сам узел nav: во ВСЕХ местах,
 * где на него смотрит игра (querySelectorAll, дальше querySelector внутри
 * заполнитьПолосу), стоит Proxy. Игра, как обычно, сама вызывает
 * `nav.innerHTML = …` и сама вешает клик через addEventListener —
 * настоящим кодом js/нижние-вкладки.js, без подсказок отсюда. Proxy
 * только ловит именно присваивание innerHTML и достраивает по нему
 * настоящие узлы (тем же разбором тегов, что и вся страница —
 * собратьРазметку), потому что это единственное место, где подделка не
 * дотягивает до настоящего браузера.
 */
function оживитьПолосыВкладок(документ) {
  документ.querySelectorAll('.нижние-вкладки[data-вкладки]').forEach(function (nav) {
    const родитель = nav.parentNode;
    const где = родитель ? родитель.childNodes.indexOf(nav) : -1;
    if (где === -1) return;
    const подмена = new Proxy(nav, {
      set: function (цель, свойство, значение) {
        if (свойство !== 'innerHTML') return Reflect.set(цель, свойство, значение);
        цель.childNodes.length = 0;
        собратьРазметку('<body>' + String(значение) + '</body>', {
          body: цель,
          createElement: function (тег) { return документ.createElement(тег); },
          createTextNode: function (т) { return документ.createTextNode(т); }
        });
        return true;
      }
    });
    родитель.childNodes[где] = подмена;
  });
}

/* Ломающий запуск --сломать-профиль: портим ТОЛЬКО исходник в памяти (файл
   на диске не трогаем) — действие «мой-счёт» жмёт несуществующую кнопку.
   Строку ищем как есть: не нашли — приём в js/нижние-вкладки.js поменялся,
   и проверка обязана громко сказать об этом, а не молча остаться зелёной. */
function сломатьДействиеПрофиля(исходник) {
  const было = "getElementById('кнопка-мой-счёт')";
  if (исходник.indexOf(было) === -1) {
    throw new Error('--сломать-профиль: в js/нижние-вкладки.js не нашлась строка «' + было + '» — приём поменялся, обновите ломающий запуск');
  }
  return исходник.split(было).join("getElementById('кнопка-мой-счёт-СЛОМАНО')");
}

/** Поддельный пункт «Настройки» Telegram: помнит, что с ним делали. */
function сделатьПунктНастроек() {
  const пункт = { виден: false, дела: [], показов: 0, прятаний: 0 };
  пункт.show = function () { пункт.виден = true; пункт.показов += 1; return пункт; };
  пункт.hide = function () { пункт.виден = false; пункт.прятаний += 1; return пункт; };
  пункт.onClick = function (д) { пункт.дела.push(д); return пункт; };
  пункт.offClick = function (д) { пункт.дела = пункт.дела.filter(function (х) { return х !== д; }); return пункт; };
  return пункт;
}

/**
 * Поднять страницу: разметка, telegram.js, game.js. telegram — добавки к WebApp
 * или null (не Telegram). подготовка(стр, этап) — вызывается до telegram.js
 * (этап «до скриптов») и между telegram.js и game.js (этап «до игры»).
 */
function поднятьСтраницу(telegram, подготовка) {
  const документ = подделка.сделатьДокумент();
  собратьРазметку(файл('index.html'), документ);
  // Подменяем узлы <nav data-вкладки="…"> на Proxy ДО того, как игра до
  // них доберётся: см. оживитьПолосыВкладок — иначе innerHTML внутри
  // js/нижние-вкладки.js ничего не построит, и настоящий обработчик клика
  // будет искать кнопку там, где её нет.
  оживитьПолосыВкладок(документ);
  const настройки = { документ: документ, имяФайла: 'страница' };
  if (telegram) настройки.telegram = telegram;
  const стр = подделка.поднять(';', настройки);
  if (подготовка) подготовка(стр, 'до скриптов');
  стр.спросить(файл('js/telegram.js'));
  /* Нижняя полоса вкладок с 12 сентября — общий модуль (js/нижние-вкладки.js),
     разметка в index.html — пустой <nav data-вкладки="…">. Файл должен
     выполниться ДО game.js (как в index.html): иначе кнопки «Рейтинг»,
     «Профиль» и их значки ещё не нарисованы, game.js их не найдёт, а
     проверка — тем более. До 12 сентября файла не было — файлЕслиЕсть
     тогда честно отдаёт null, и страница живёт со старой ручной разметкой. */
  const вкладки = файлЕслиЕсть('js/нижние-вкладки.js');
  if (вкладки) стр.спросить(сломатьПрофиль ? сломатьДействиеПрофиля(вкладки) : вкладки);
  /* Лист «Ещё» стола/партии — общий модуль (Э7, 17 сентября), грузится
     перед game.js — как в index.html. Без него «подключитьЛистИгры»
     внутри game.js тихо выходит (window.ЛистЕщё не найден), и обёртки
     открытьЛистИгры/закрытьЛистИгры/листИгрыОткрыт не работают. */
  const листЕщё = файлЕслиЕсть('js/лист-ещё.js');
  if (листЕщё) стр.спросить(листЕщё);
  /* Путь дурака (лобби и три шага) грузится перед game.js — как в index.html.
     Без него game.js берёт запасной вход в лобби, и проверка смотрела бы
     не на ту страницу, что у игрока. */
  const путь = файлЕслиЕсть('js/дурак-путь.js');
  if (путь) стр.спросить(путь);
  if (подготовка) подготовка(стр, 'до игры');
  стр.спросить(файл('js/game.js'));
  return стр;
}

let провалов = 0;
function проверить(условие, что) {
  if (!условие) провалов += 1;
  console.log((условие ? '  ок   ' : '  ПРОВАЛ ') + что);
}

/** Раздел проверки: обрыв с ошибкой — тоже провал, но прогон идёт дальше. */
function раздел(имя, дело) {
  console.log(имя);
  try {
    дело();
  } catch (беда) {
    провалов += 1;
    console.log('  ПРОВАЛ раздел оборвался: ' + (беда && беда.message ? беда.message : String(беда)));
  }
}

function видна(документ, id) {
  const у = документ.getElementById(id);
  return Boolean(у) && !у.classList.contains('скрыт');
}

function нажать(документ, id) {
  const у = документ.getElementById(id);
  if (!у) return false;
  у.click();
  return true;
}

