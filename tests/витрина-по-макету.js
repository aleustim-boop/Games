/** Простой разбор разметки тела страницы: теги, атрибуты в двойных кавычках, текст. */
function собратьРазметку(html, документ) {
  const чистый = html.replace(/<!--[\s\S]*?-->/g, '').replace(/<script[\s\S]*?<\/script>/g, '');
  const тело = /<body[^>]*>([\s\S]*)<\/body>/.exec(чистый)[1];
  const образец = /<(\/?)([a-zA-Z][\w-]*)([^>]*?)(\/?)>|([^<]+)/g;
  const ПУСТЫЕ = new Set(['input', 'br', 'img', 'meta', 'link', 'hr']);
  const стек = [документ.body];
  let м;
  while ((м = образец.exec(тело))) {
    if (м[5] !== undefined) {
      if (м[5].trim()) стек[стек.length - 1].appendChild(документ.createTextNode(м[5]));
      continue;
    }
    const тег = м[2].toLowerCase();
    if (м[1] === '/') {
      for (let i = стек.length - 1; i > 0; i--) if (стек[i].tagName === тег.toUpperCase()) { стек.length = i; break; }
      continue;
    }
    const узел = документ.createElement(тег);
    const атр = /([^\s=]+)(?:\s*=\s*"([^"]*)")?/g;
    let а;
    while ((а = атр.exec(м[3]))) {
      узел.setAttribute(а[1], а[2] === undefined ? '' : а[2]);
      if (а[1] === 'disabled') узел.disabled = true;
    }
    стек[стек.length - 1].appendChild(узел);
    if (м[4] !== '/' && !ПУСТЫЕ.has(тег)) стек.push(узел);
  }
}

/** Поддельный пункт «Настройки» Telegram: помнит, что с ним делали. */
function сделатьПунктНастроек() {
  const пункт = { виден: false, дела: [], показов: 0, прятаний: 0 };
  пункт.show = function () { пункт.виден = true; пункт.показов += 1; return пункт; };
  пункт.hide = function () { пункт.виден = false; пункт.прятаний += 1; return пункт; };
  пункт.onClick = function (д) { пункт.дела.push(д); return пункт; };
  пункт.offClick = function (д) { пункт.дела = пункт.дела.filter(function (х) { return х !== д; }); return пункт; };
  return пункт;
}

/**
 * Поднять страницу: разметка, telegram.js, game.js. telegram — добавки к WebApp
 * или null (не Telegram). подготовка(стр, этап) — вызывается до telegram.js
 * (этап «до скриптов») и между telegram.js и game.js (этап «до игры»).
 */
function поднятьСтраницу(telegram, подготовка) {
  const документ = подделка.сделатьДокумент();
  собратьРазметку(файл('index.html'), документ);
  const настройки = { документ: документ, имяФайла: 'страница' };
  if (telegram) настройки.telegram = telegram;
  const стр = подделка.поднять(';', настройки);
  if (подготовка) подготовка(стр, 'до скриптов');
  стр.спросить(файл('js/telegram.js'));
  if (подготовка) подготовка(стр, 'до игры');
  стр.спросить(файл('js/game.js'));
  return стр;
}

let провалов = 0;
function проверить(условие, что) {
  if (!условие) провалов += 1;
  console.log((условие ? '  ок   ' : '  ПРОВАЛ ') + что);
}

/** Раздел проверки: обрыв с ошибкой — тоже провал, но прогон идёт дальше. */
function раздел(имя, дело) {
  console.log(имя);
  try {
    дело();
  } catch (беда) {
    провалов += 1;
    console.log('  ПРОВАЛ раздел оборвался: ' + (беда && беда.message ? беда.message : String(беда)));
  }
}

function видна(документ, id) {
  const у = документ.getElementById(id);
  return Boolean(у) && !у.classList.contains('скрыт');
}

function нажать(документ, id) {
  const у = документ.getElementById(id);
  if (!у) return false;
  у.click();
  return true;
}

