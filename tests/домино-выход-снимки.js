/** Плашка листа «⋯»: дверь «завершить» отдаёт слова выхода — заголовок, кнопки и последствие про бота. */
async function разобратьПлашку(страница, п) {
  const м = await страница.evaluate(замерить, [ПЛАШКА.окно, ПЛАШКА.заголовок, ПЛАШКА.текст, ПЛАШКА.да, ПЛАШКА.нет]);
  const о = м.узлы[ПЛАШКА.окно], з = м.узлы[ПЛАШКА.заголовок], т = м.узлы[ПЛАШКА.текст], да = м.узлы[ПЛАШКА.да], нет = м.узлы[ПЛАШКА.нет];
  if (!проверить(о.есть && з.есть && т.есть && да.есть && нет.есть && о.виден, п + '[а2] плашка «⋯» найдена и видна (окно ' + о.есть + ', заголовок ' + з.есть + ', текст ' + т.есть + ', кнопки ' + да.есть + '/' + нет.есть + ')')) return;
  проверить(з.текст === НОВЫЕ.заголовок, п + '[а2] заголовок плашки «' + НОВЫЕ.заголовок + '» (на экране «' + з.текст + '»)');
  проверить(да.текст === НОВЫЕ.да, п + '[а2] опасная кнопка плашки «' + НОВЫЕ.да + '» (на экране «' + да.текст + '»)');
  проверить(нет.текст === НОВЫЕ.нет, п + '[а2] кнопка «нет» плашки «' + НОВЫЕ.нет + '» (на экране «' + нет.текст + '»)');
  проверить(!/Завершить/.test(з.текст + ' ' + да.текст), п + '[а2] слов «Завершить» в плашке выхода нет');
  проверить(т.текст === НОВЫЕ.текст, п + '[а2] в плашке текст про бота и возврат (на экране «' + т.текст + '»)');
  проверить(о.вЭкране, п + '[а2] плашка целиком в экране (' + кратко(о) + ', экран ' + м.W + '×' + м.H + ')');
  проверить(т.виден && !т.обрезан, п + '[а2] текст плашки не обрезан (' + т.размеры + ')');
  const к = await страница.evaluate(кнопкиВнутри, '.плашка-завершить__окно');
  проверить(к.кнопки.length >= 2 && к.кнопки.every(function (б) { return б.вЭкране && б.сверху && б.h >= МИН_ВЫСОТА_КНОПКИ - 0.5 && !б.обрезан; }),
    п + '[а2] кнопки плашки в экране, не перекрыты, ≥ ' + МИН_ВЫСОТА_КНОПКИ + ', не обрезаны (' + к.кнопки.map(function (б) { return '«' + б.текст + '» ' + б.h; }).join(', ') + ')');
  проверить(м.прокруткаВбок <= 0, п + '[а2] горизонтальной прокрутки страницы нет (' + м.прокруткаВбок + ')');
}

async function разобратьКонец(страница, п) {
  const узлы = ['#дом-результат', '#дом-итог-заголовок', '#дом-итог-подпись', '#дом-дальше', '#дом-посмотреть', '#дом-в-лобби'];
  const м = await страница.evaluate(замерить, узлы);
  const о = м.узлы['#дом-результат'], з = м.узлы['#дом-итог-заголовок'];
  if (!проверить(о.есть && з.есть && о.диалогОткрыт === true, п + '[в] окно итога найдено и открыто (окно ' + о.есть + ', заголовок ' + з.есть + ', открыто ' + о.диалогОткрыт + ')')) return;
  проверить(з.виден && з.текст === СЛОВА_КОНЦА, п + '[в] заголовок — «' + СЛОВА_КОНЦА + '» (на экране «' + з.текст + '»)');
  проверить(з.вЭкране && !з.обрезан, п + '[в] заголовок в экране и не обрезан (' + з.размеры + ')');
  проверить(о.вЭкране, п + '[в] окно итога целиком в экране (' + кратко(о) + ', экран ' + м.W + '×' + м.H + ')');
  const слова = await страница.evaluate(всёСлова);
  проверить(слова.length > 50 && !/undefined|NaN/.test(слова), п + '[в] на экране нет «undefined» и «NaN» (текста проверено: ' + слова.length + ' знаков)');
  проверить(!/победили|Партия завершена(?! по)/i.test(з.текст), п + '[в] заголовок — не «победа» и не «Партия завершена»');
  const к = await страница.evaluate(кнопкиВнутри, '#дом-результат');
  проверить(к.кнопки.length >= 2, п + '[в] в окне итога найдены кнопки (' + к.кнопки.map(function (б) { return '«' + б.текст + '»'; }).join(', ') + ')');
  проверить(к.кнопки.length > 0 && к.кнопки.every(function (б) { return б.вЭкране && б.сверху && б.h >= МИН_ВЫСОТА_КНОПКИ - 0.5 && !б.обрезан; }),
    п + '[в] кнопки итога видны без прокрутки, не перекрыты, ≥ ' + МИН_ВЫСОТА_КНОПКИ + ', не обрезаны (' + к.кнопки.map(function (б) { return б.y + '–' + б.b + ' h' + б.h; }).join(', ') + ')');
  проверить(м.прокруткаВбок <= 0, п + '[в] горизонтальной прокрутки страницы нет (' + м.прокруткаВбок + ')');
}

async function разобратьСоседа(страница, п) {
  const м = await страница.evaluate(замерить, ['#дом-подсказка', '#экран-игры']);
  const с = м.узлы['#дом-подсказка'], э = м.узлы['#экран-игры'];
  if (!проверить(с.есть && э.есть && э.виден, п + '[г] стол и строка подсказки найдены (подсказка ' + с.есть + ', стол виден ' + э.виден + ')')) return;
  проверить(с.виден && с.текст === СЛОВА_СОСЕДА, п + '[г] слова о соседе видны: «' + СЛОВА_СОСЕДА + '» (на экране «' + с.текст + '»)');
  проверить(с.вЭкране, п + '[г] строка подсказки целиком в экране (' + кратко(с) + ', экран ' + м.W + '×' + м.H + ')');
  проверить(!с.обрезан, п + '[г] слова о соседе не обрезаны (прокрутка / размер: ' + с.размеры + ')');
  проверить(м.прокруткаВбок <= 0, п + '[г] горизонтальной прокрутки страницы нет (' + м.прокруткаВбок + ')');
  const слова = await страница.evaluate(всёСлова);
  проверить(!/undefined|NaN/.test(слова), п + '[г] на экране нет «undefined» и «NaN»');
}

/* ---------- Прогон ---------- */

async function прогнать(подменаЭкрана, папка) {
  fs.mkdirSync(папка, { recursive: true });
  проверить(СТАРЫЕ.заголовок.length > 3 && СТАРЫЕ.текст.length > 20 && СТАРЫЕ.да.length > 2 && СТАРЫЕ.нет.length > 2, 'прежние слова окна выхода прочитаны из домино.html («' + СТАРЫЕ.заголовок + '»)');
  // Вдвоём поля «досрочно» сервер не шлёт; но и если бы прислал, слов про бота быть не должно (б2).
  const в3 = вид(3), в2 = вид(2, { досрочно: null }), в2сПолем = вид(2), вК = видКонца();
  проверить(в3.досрочно && typeof в3.досрочно === 'object' && !в2.досрочно, 'вид от 3 мест несёт поле «досрочно», вид вдвоём — нет');
  проверить(вК.домино.фаза === 'конец' && вК.домино.прерван === true, 'вид конца: партия прервана');
  const сервер = await поднятьСерверФайлов(подменаЭкрана);
  const адрес = 'http://127.0.0.1:' + сервер.address().port + '/';
  console.log('=== Домино: выход с ботом — снимки и замеры ===');
  console.log('файлы: ' + адрес + (подменаЭкрана ? '  (экран подменён: ' + подменаЭкрана + ')' : '') + '\nснимки: ' + папка);
  let браузер = null;
  try {
    браузер = await chromium.launch();
    for (const размер of РАЗМЕРЫ) {
      await случай(браузер, адрес, размер, 'а', 'выход-3-места-окно', [в3], папка, нажатьНазад, разобратьТриМеста);
      await случай(браузер, адрес, размер, 'а2', 'выход-3-места-лист', [в3], папка, нажатьЗавершить, разобратьПлашку);
      await случай(браузер, адрес, размер, 'б', 'выход-вдвоём', [в2], папка, нажатьНазад, разобратьВдвоём);
      await случай(браузер, адрес, размер, 'б2', 'выход-вдвоём-с-полем', [в2сПолем], папка, нажатьНазад, разобратьВдвоём);
      await случай(браузер, адрес, размер, 'в', 'конец-по-согласию', [вК], папка, null, разобратьКонец);
      await случай(браузер, адрес, размер, 'г', 'сосед-вышел-бот', [
        вид(3, { застолом: стол(), номерСобытия: 5 }),
        вид(3, { застолом: стол({ ушёл: true, этоБот: true }), номерСобытия: 6 })
      ], папка, null, разобратьСоседа);
    }
  } finally {
    if (браузер) await браузер.close();
    сервер.close();
    fs.rmSync(process.env.ДАННЫЕ_ИГРЫ, { recursive: true, force: true });
    console.log('\nСервер файлов закрыт.');
  }
  console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
  process.exitCode = провалов > 0 ? 1 : 0;
}

