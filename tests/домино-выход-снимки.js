/** В СТРАНИЦЕ: замер узла по css-селектору. Не найден — { есть: false }. */
function замерить(селекторы) {
  const W = document.documentElement.clientWidth, H = window.innerHeight;
  const итог = { W: W, H: H, прокруткаВбок: document.documentElement.scrollWidth - W, узлы: {} };
  селекторы.forEach(function (сел) {
    const у = document.querySelector(сел);
    if (!у) { итог.узлы[сел] = { есть: false }; return; }
    const р = у.getBoundingClientRect(), с = getComputedStyle(у);
    const диалог = у.closest('dialog');
    const ц = document.elementFromPoint((р.left + р.right) / 2, (р.top + р.bottom) / 2);
    итог.узлы[сел] = {
      есть: true, текст: у.textContent.trim(),
      виден: с.display !== 'none' && с.visibility !== 'hidden' && р.width > 0 && р.height > 0 && !у.closest('.скрыт'),
      x: р.left, y: р.top, r: р.right, b: р.bottom, w: р.width, h: р.height,
      вЭкране: р.left >= -0.5 && р.top >= -0.5 && р.right <= W + 0.5 && р.bottom <= H + 0.5,
      обрезан: у.scrollWidth > у.clientWidth + 1 || у.scrollHeight > у.clientHeight + 3,
      размеры: у.scrollWidth + '×' + у.scrollHeight + ' / ' + у.clientWidth + '×' + у.clientHeight,
      сверху: Boolean(ц) && (у === ц || у.contains(ц)),
      вДиалоге: диалог ? (function () { const д = диалог.getBoundingClientRect(); return р.left >= д.left - 0.5 && р.top >= д.top - 0.5 && р.right <= д.right + 0.5 && р.bottom <= д.bottom + 0.5; })() : null,
      диалогОткрыт: диалог ? диалог.open : null
    };
  });
  return итог;
}

/** В СТРАНИЦЕ: все видимые кнопки внутри корня (селектор) с замерами. */
function кнопкиВнутри(корень) {
  const W = document.documentElement.clientWidth, H = window.innerHeight;
  const к = document.querySelector(корень);
  if (!к) return { есть: false, кнопки: [], H: H };
  const кнопки = Array.from(к.querySelectorAll('button')).filter(function (б) {
    const р = б.getBoundingClientRect(), с = getComputedStyle(б);
    return с.display !== 'none' && с.visibility !== 'hidden' && р.width > 0 && р.height > 0 && !б.closest('.скрыт');
  }).map(function (б) {
    const р = б.getBoundingClientRect();
    const ц = document.elementFromPoint((р.left + р.right) / 2, (р.top + р.bottom) / 2);
    return { текст: б.textContent.trim(), y: Math.round(р.top), b: Math.round(р.bottom), h: Math.round(р.height),
      вЭкране: р.left >= -0.5 && р.top >= -0.5 && р.right <= W + 0.5 && р.bottom <= H + 0.5,
      сверху: Boolean(ц) && (б === ц || б.contains(ц)),
      обрезан: б.scrollWidth > б.clientWidth + 1 };
  });
  return { есть: true, кнопки: кнопки, H: H };
}

