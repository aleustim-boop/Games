'use strict';
/* =====================================================================
   ЖИВЫЕ ЛОББИ: лимит личин режиссёра и таймер, не держащий процесс
   (server/живые-лобби.js). Без сети и без сервера, на настоящем модуле комнат.

   Проверяем:
     А. лимит личин (ЛОББИ_МАКС_ЛИЧИН=4) считается по ОЖИДАЮЩИМ столам:
        на каждом шаге за столами режиссёра сидит не больше 4 личин, одна
        личина — за одним столом, и лимит при этом реально выбирается
        (3–4 личины, а не ноль: «ничего не открыл» не считается соблюдением);
     Б. живой состав: за столом сел человек — режиссёр его отпускает, а
        личины этого стола заняты партией: за новые ожидающие столы они не
        садятся (ожидающих личин на столько меньше, лимит не превышен);
     В. таймер режиссёра не держит процесс: и первый, и следующие таймеры
        имеют hasRef() === false (иначе сервер из проверки не завершится сам).

   Запуск:  node tests/живые-лобби-лимит-личин.js
   Ломающие запуски (порча в ПАМЯТИ, файлы проекта не трогаем; каждый обязан
   покраснеть в названном разделе, иначе выход с кодом 3):
     --сломать=лимит    режиссёр: личин за столами не считает и пул не ограничен — раздел А
     --сломать=живой    режиссёр: занятые партией личины годятся на новые столы — раздел Б
     --сломать=таймер   режиссёр: таймер не отцепляется от процесса — раздел В
   ===================================================================== */

const path = require('path');
const os = require('os');
const fs = require('fs');
const Module = require('module');

process.env.ДАННЫЕ_ИГРЫ = path.join(os.tmpdir(), 'живые-лобби-лимит-' + process.pid);
delete process.env.ЛИЧИНЫ;
delete process.env.ЛОББИ_ЛИЧИН;
delete process.env.ЛОББИ_МАКС_ЛИЧИН;
delete process.env.ЛОББИ_ПОРОГ_ЛЮДЕЙ;
delete process.env.ЛОББИ_СТОЛОВ;

const КОРЕНЬ = path.join(__dirname, '..');
const аргументПорчи = process.argv.find(function (а) { return а === '--сломать' || а.indexOf('--сломать=') === 0; });
const ПОРЧА = аргументПорчи ? (аргументПорчи.split('=')[1] || 'лимит') : null;

/* Жребий с зерном: проверка воспроизводима. */
let зерно = 20261004;
Math.random = function () {
  зерно = (зерно + 0x6D2B79F5) | 0;
  let t = Math.imul(зерно ^ (зерно >>> 15), 1 | зерно);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};

/* Учёт таймеров: записываем всё, что поставлено, пока включена запись. */
const настоящийSetTimeout = global.setTimeout;
const настоящийClearTimeout = global.clearTimeout;
const поставленныеТаймеры = new Set();
let записывать = false;
global.setTimeout = function () {
  const таймер = настоящийSetTimeout.apply(global, arguments);
  if (записывать) поставленныеТаймеры.add(таймер);
  return таймер;
};
global.clearTimeout = function (таймер) {
  return настоящийClearTimeout.call(global, таймер);
};

/* Порчи: файл, что заменить (ровно одно место), чем, в каком разделе обязано покраснеть. */
const ПОРЧИ = {
  /* Лимит держат два слоя: подсчёт личин за столами и размер пула личин.
     Порча снимает оба, иначе второй слой прикрыл бы первый. */
  'лимит': {
    файл: ['server', 'живые-лобби.js'],
    замены: [
      { было: 'if (стол.людей === 0) сумма += стол.личины.length;', стало: '/* порча: личин за столами не считаем */' },
      { было: 'пул = личины.пулЛобби(сколько);', стало: 'пул = личины.пулЛобби(100);   /* порча: пул не ограничен */' }
    ],
    раздел: 'А',
    описание: 'лимит личин не действует — раздел А обязан покраснеть'
  },
  'живой': {
    файл: ['server', 'живые-лобби.js'],
    замены: [
      { было: 'return !занятые.has(л.номер);', стало: 'return true;   /* порча: занятые личины годятся */' }
    ],
    раздел: 'Б',
    описание: 'личины стола с человеком снова идут на новые столы — раздел Б обязан покраснеть'
  },
  'таймер': {
    файл: ['server', 'живые-лобби.js'],
    замены: [
      { было: "if (таймер && typeof таймер.unref === 'function') таймер.unref();", стало: '/* порча: таймер держит процесс */' }
    ],
    раздел: 'В',
    описание: 'таймер режиссёра держит процесс — раздел В обязан покраснеть'
  }
};

if (ПОРЧА) {
  const порча = ПОРЧИ[ПОРЧА];
  if (!порча) { console.log('неизвестная порча: ' + ПОРЧА); process.exit(2); }
  const путь = path.join.apply(path, [КОРЕНЬ].concat(порча.файл));
  let текст = fs.readFileSync(путь, 'utf8').replace(/\r\n/g, '\n');
  for (const замена of порча.замены) {
    if (текст.split(замена.было).length !== 2) { console.log('порча не применилась (место не найдено ровно один раз): ' + замена.было); process.exit(2); }
    текст = текст.replace(замена.было, function () { return замена.стало; });
  }
  const м = new Module(путь, module);
  м.filename = путь;
  м.paths = Module._nodeModulePaths(path.dirname(путь));
  м._compile(текст, путь);
  require.cache[путь] = м;
  м.loaded = true;
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: ' + порча.описание + ' ***');
}

const комнаты = require(path.join(КОРЕНЬ, 'server', 'комнаты.js'));
const режиссёр = require(path.join(КОРЕНЬ, 'server', 'живые-лобби.js'));

let проверок = 0;
let номерРаздела = '';
const провалы = [];
function проверить(условие, что) {
  проверок++;
  if (!условие) { провалы.push({ раздел: номерРаздела, что: что }); console.log('  ПРОВАЛ: ' + что); }
}
function раздел(номер, название) {
  номерРаздела = номер;
  console.log(номер + '. ' + название);
}

const НАЧАЛО = 1000000000000;
const ШАГ_МС = 7000;
const ЛИМИТ = 4;

function очистить() {
  for (const стол of режиссёр.моиСтолы()) комнаты.закрытьСтолЛичин(стол.код);
  режиссёр.остановить();
}
function запуститьЧисто() {
  очистить();
  режиссёр.запустить(комнаты, function () { return 0; });
}
function личныеНомера() {
  const все = [];
  for (const стол of режиссёр.моиСтолы()) for (const н of стол.личины) all(все, н);
  return все;
}
function all(список, н) { список.push(н); }

/* ---------- А. Лимит по ожидающим столам ---------- */
раздел('А', 'Лимит личин ' + ЛИМИТ + ' по ожидающим столам');
process.env.ЛОББИ_МАКС_ЛИЧИН = String(ЛИМИТ);
запуститьЧисто();
{
  let худшее = 0;
  let время = НАЧАЛО;
  for (let i = 0; i < 40; i++) {
    режиссёр.шаг(время);
    время += ШАГ_МС;
    const номера = личныеНомера();
    худшее = Math.max(худшее, номера.length);
    if (номера.length > ЛИМИТ) { проверить(false, 'на шаге ' + (i + 1) + ' за столами ' + номера.length + ' личин при лимите ' + ЛИМИТ); break; }
    if (new Set(номера).size !== номера.length) { проверить(false, 'на шаге ' + (i + 1) + ' одна личина за двумя столами'); break; }
  }
  const итоговых = личныеНомера().length;
  проверить(итоговых >= 3 && итоговых <= ЛИМИТ, 'лимит выбран: за столами ' + итоговых + ' личин (ждали 3–' + ЛИМИТ + ', худшее за прогон ' + худшее + ')');
  проверить(режиссёр.моиСтолы().length >= 2, 'столов открыто ' + режиссёр.моиСтолы().length + ', ждали хотя бы 2');
}

/* ---------- Б. Живой состав: человек сел — личины стола не считаются ---------- */
раздел('Б', 'Человек сел за стол — его личины из лимита выпадают');
{
  const до = личныеНомера().length;
  const столыДо = режиссёр.моиСтолы();
  const цель = столыДо.find(function (с) { return с.игра === 'шашки'; }) || столыДо[0];
  проверить(!!цель, 'есть стол, за который можно посадить человека');
  if (цель) {
    const вход = комнаты.войтиВКомнату(цель.код, { имя: 'Гость', метка: 'метка-лимит-личин-1' });
    проверить(вход && вход.ок === true, 'человек сел за стол режиссёра по коду');
    const времяСдвига = НАЧАЛО + 41 * ШАГ_МС;
    режиссёр.шаг(времяСдвига);
    проверить(!режиссёр.моиСтолы().some(function (с) { return с.код === цель.код; }), 'режиссёр отпустил стол с человеком');
    let время = времяСдвига;
    let худшее = 0;
    for (let i = 0; i < 30; i++) {
      время += ШАГ_МС;
      режиссёр.шаг(время);
      худшее = Math.max(худшее, личныеНомера().length);
    }
    const после = личныеНомера();
    проверить(худшее <= ЛИМИТ, 'и после посадки за ожидающими столами не больше ' + ЛИМИТ + ' личин (было ' + худшее + ')');
    /* Живой состав: личины стола с человеком заняты партией и пойти на новые столы не могут,
       поэтому ожидающих личин стало ровно на столько меньше, сколько их за столом с человеком. */
    const занятыеЛичины = цель.личины;
    проверить(занятыеЛичины.length >= 1, 'у стола с человеком есть личины (' + занятыеЛичины.length + ')');
    проверить(после.length === до - занятыеЛичины.length, 'ожидающих личин: было ' + до + ', стало ' + после.length +
      ', ждали ' + (до - занятыеЛичины.length) + ' (личины стола с человеком не возвращаются в лимит и не сидят за новыми столами)');
    проверить(занятыеЛичины.every(function (н) { return !после.includes(н); }),
      'личина из партии с человеком (№' + занятыеЛичины.join(',') + ') не должна сидеть за ожидающим столом');
    проверить(режиссёр.моиСтолы().every(function (с) { return с.код !== цель.код; }), 'стол с человеком не вернулся в список режиссёра');
  }
}
очистить();
delete process.env.ЛОББИ_МАКС_ЛИЧИН;

/* ---------- В. Таймер не держит процесс ---------- */
раздел('В', 'Таймер режиссёра не держит процесс (hasRef)');
очистить();
поставленныеТаймеры.clear();
записывать = true;
режиссёр.запустить(комнаты, function () { return 0; });
записывать = false;
{
  const первые = Array.from(поставленныеТаймеры);
  проверить(первые.length === 1, 'после запуска поставлен ровно один таймер (поставлено ' + первые.length + ')');
  проверить(первые.length > 0 && первые.every(function (т) { return typeof т.hasRef === 'function' && т.hasRef() === false; }),
    'первый таймер держит процесс (hasRef не false)');
}
/* Ждём, пока сработает первый шаг (через ~2 с) и режиссёр заведёт следующий таймер. */
записывать = true;
настоящийSetTimeout(function () {
  записывать = false;
  const все = Array.from(поставленныеТаймеры);
  проверить(все.length >= 2, 'после первого шага заведён следующий таймер (всего таймеров ' + все.length + ')');
  проверить(все.length > 0 && все.every(function (т) { return typeof т.hasRef === 'function' && т.hasRef() === false; }),
    'следующий таймер режиссёра держит процесс (hasRef не false)');
  очистить();
  завершить();
}, 2600).ref();

function завершить() {
  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалы.length);
  if (ПОРЧА) {
    const порча = ПОРЧИ[ПОРЧА];
    const пойман = провалы.some(function (п) { return п.раздел === порча.раздел; });
    console.log(пойман ? 'Порча поймана: проверка покраснела как надо' : 'ПОРЧА НЕ ПОЙМАНА: нужный раздел остался зелёным');
    process.exit(пойман ? 1 : 3);
  }
  process.exit(провалы.length ? 1 : 0);
}
