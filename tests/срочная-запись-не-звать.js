#!/usr/bin/env node
'use strict';

/* =====================================================================
   СРОЧНАЯ ЗАПИСЬ «НЕ ЗВАТЬ»: отказ человека («сам») должен лечь на диск
   сразу, а не через пять секунд. Отказ бота («ботНеПишет») — по-прежнему
   может подождать.

   Та же беда, что чинилась в server/рейтинг.js, server/сила-игроков.js
   и server/раздача-дня.js (см. соответствующие tests/срочная-запись-*.js),
   была и в server/не-звать.js: обе причины отказа писались на диск
   отложенно (ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ = 5000). Человек нажал в письме бота
   «Не звать меня», сервер упал в ближайшие пять секунд — и после
   перезапуска отказа как не бывало: письма бота снова находят человека,
   который явно попросил их прекратить.

   ПОЧЕМУ ЗДЕСЬ ЕСТЬ РАЗДЕЛЕНИЕ «ВАЖНОЕ / МЕЛОЧЬ», в отличие от силы и
   раздачи дня, но как в очках рейтинга. Причина 'сам' — решение человека,
   бессрочное, и потерять его стыдно. Причина 'ботНеПишет' — не решение,
   а состояние Telegram, и она и так живёт только сутки: потеряться при
   падении ей не страшно, бот просто попробует написать ещё раз. Штаб
   решил чинить срочной записью только 'сам' (см. запретить в
   server/не-звать.js, строки ~245-257) и оставить 'ботНеПишет' отложенной
   нарочно — если завтра кто-то сделает срочным всё подряд, диск начнёт
   дёргаться на каждое недоставленное письмо бота, а решение штаба
   потеряется молча. Вот это и стережём: проверка обязана покраснеть не
   только если 'сам' разучится быть срочной, но и если развилка исчезнет
   в другую сторону и 'ботНеПишет' внезапно тоже станет немедленной —
   такое молчаливое расширение здесь считается поломкой, а не улучшением.

   КАК ПРОВЕРЯЕМ «упало сразу после отказа», не дожидаясь настоящего
   падения и не ожидая реальных пяти секунд: запрет ставится в ОТДЕЛЬНОМ
   процессе node, который завершается через process.exit(0) сразу после
   запретить(...) — без вызова дописать(). Если запись должна была лечь
   на диск немедленно (записатьСрочно) — writeFileSync успевает
   отработать ДО exit(0), и файл на диске есть. Если запись отложенная —
   таймер помечен .unref() и точно так же не переживает жёсткое
   завершение процесса, поэтому файла не будет вовсе.

   ЧТО ПРОВЕРЯЕМ:
     1) отказ 'сам' (человек нажал «Не звать меня») — после «падения»
        сразу после запретить() запись на диске ЕСТЬ, с причиной 'сам';
     2) отказ 'ботНеПишет' (Telegram не доставил письмо) — при том же
        самом «падении» на диске по-прежнему НИЧЕГО НЕТ: развилка не
        выродилась в «всё срочно», суточная пометка бота как была
        отложенной, так и осталась.

   УМЕЕТ ЛИ ОНА КРАСНЕТЬ. node tests/срочная-запись-не-звать.js --сломать
   берёт временную копию server/не-звать.js и возвращает ветку 'сам'
   обратно на отложенную запись (записатьпогодя() вместо развилки
   «сам — срочно, ботНеПишет — погодя») — ровно та поломка, из-за которой
   бессрочный отказ человека может пропасть при падении сервера. На такой
   копии пункт (1) обязан провалиться: записи на диске сразу после
   «падения» уже не будет.

   Боевых данных не касается: копия server/ и папка данных — во временных
   каталогах (mkdtempSync), каждый запрет ставится в отдельном дочернем
   процессе node, чтобы «падение сразу после exit» было настоящим, а не
   догадкой по логике кода.

   Запуск:
     node tests/срочная-запись-не-звать.js             (обычный прогон)
     node tests/срочная-запись-не-звать.js --сломать   (обязан провалиться)
   Выход 0 — провалов нет, 1 — провал (смотреть строки «ПРОВАЛ» в выводе).
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const СЛОМАТЬ = process.argv.includes('--сломать');

const ПРОВЕРКИ = [];
function проверить(имя, условие, подробности) {
  ПРОВЕРКИ.push({ имя: имя, ошибка: условие ? null : (подробности || 'условие не выполнено') });
}

/* Все временные папки этого прогона (копия server/ и по одной у каждого
   дочернего раннера) — чтобы убрать их за собой в самом конце, а не
   оставлять мусор во временной папке ОС на каждый запуск. */
const ВСЕ_ВРЕМЕННЫЕ_ПАПКИ = [];

/** Своя временная папка с заданным префиксом — и сразу на учёт для уборки. */
function новаяВременнаяПапка(префикс) {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), префикс));
  ВСЕ_ВРЕМЕННЫЕ_ПАПКИ.push(папка);
  return папка;
}

/* Убираем СВОИ временные папки по любому выходу процесса —
   process.on('exit') срабатывает и на process.exit(), и на непойманную
   ошибку. Раньше эти папки никогда не удалялись и копились на диске. */
process.on('exit', function () {
  for (const папка of ВСЕ_ВРЕМЕННЫЕ_ПАПКИ) {
    try { fs.rmSync(папка, { recursive: true, force: true, maxRetries: 3 }); } catch (е) { /* не страшно */ }
  }
});

/** Своя копия server/ во временной папке — боевой код и боевые данные не трогаем. */
function подготовитьКопиюСервера() {
  const врем = новаяВременнаяПапка('срочная-запись-не-звать-');
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(врем, 'server'), { recursive: true });
  return path.join(врем, 'server', 'не-звать.js');
}

/**
 * Порча копии: возвращает ветку 'сам' обратно на отложенную запись —
 * ровно та регрессия, от которой предостерегает штаб. После порчи обе
 * причины пишутся отложенно, как было до починки.
 */
function испортитьКопию(путьКНеЗвать) {
  const исходник = fs.readFileSync(путьКНеЗвать, 'utf8');
  const было = '  if (слово === ПРИЧИНЫ.сам) записатьСрочно();\n  else записатьпогодя();';
  if (исходник.indexOf(было) === -1) {
    throw new Error('не нашёл развилку записи для порчи — код server/не-звать.js изменился, поправьте tests/срочная-запись-не-звать.js');
  }
  const испорчено = исходник.replace(было,
    '  записатьпогодя(); /* ИСПОРЧЕНО ПРОВЕРКОЙ tests/срочная-запись-не-звать.js --сломать: причина «сам» снова ждёт 5 секунд */');
  fs.writeFileSync(путьКНеЗвать, испорчено, 'utf8');
}

/**
 * Содержимое раннера: в отдельном процессе ставит один запрет и СРАЗУ
 * завершается через process.exit(0), без дописать() — это и есть модель
 * «сервер упал в первую же миллисекунду после отказа человека».
 */
function кодРаннера(папкаДанных, путьКНеЗвать, номер, причина) {
  return [
    "process.env.GAMES_DATA = " + JSON.stringify(папкаДанных) + ";",
    "const неЗвать = require(" + JSON.stringify(путьКНеЗвать) + ");",
    "неЗвать.включитьЗапись();",
    "неЗвать.запретить(" + JSON.stringify(номер) + ", " + JSON.stringify(причина) + ");",
    "process.exit(0);"
  ].join('\n');
}

/** Поставить запрет в отдельном процессе и вернуть, что осталось на диске. */
function запретитьВОтдельномПроцессе(путьКНеЗвать, номер, причина) {
  const врем = новаяВременнаяПапка('срочная-запись-не-звать-раннер-');
  const папкаДанных = path.join(врем, 'данные');
  const файлРаннера = path.join(врем, 'раннер.js');
  fs.writeFileSync(файлРаннера, кодРаннера(папкаДанных, путьКНеЗвать, номер, причина), 'utf8');

  execFileSync(process.execPath, [файлРаннера], { stdio: 'pipe' });

  const файлНеЗвать = path.join(папкаДанных, 'не-звать.json');
  if (!fs.existsSync(файлНеЗвать)) return null;
  return JSON.parse(fs.readFileSync(файлНеЗвать, 'utf8'));
}

/** Запись игрока в прочитанном файле «не звать» (или null, если записи нет). */
function записьИгрока(данные, номер) {
  if (!данные || !Array.isArray(данные.запреты)) return null;
  return данные.запреты.find(function (з) { return з.номер === номер; }) || null;
}

/* -----------------------------------------------------------------------
   main
   ----------------------------------------------------------------------- */

// Путь к копии не-звать.js: свой довод командной строки, по умолчанию —
// собственная временная копия server/ (боевой файл не трогаем).
const путьИзДовода = process.argv.find(function (а, я) {
  return я >= 2 && !а.startsWith('--');
});
const путьКНеЗвать = путьИзДовода || подготовитьКопиюСервера();
if (СЛОМАТЬ) испортитьКопию(путьКНеЗвать);

/* Сценарий 1: человек сам нажал «Не звать меня» — бессрочный отказ,
   потерять который стыдно. Должен лечь на диск немедленно. */
const данные1 = запретитьВОтдельномПроцессе(путьКНеЗвать, 4001, 'сам');
const запись1 = записьИгрока(данные1, 4001);

проверить(
  'отказ «сам» есть на диске сразу после «падения» процесса',
  !!запись1 && запись1.причина === 'сам',
  данные1 === null
    ? 'файл «не звать» вообще не появился — бессрочный отказ человека потерялся'
    : 'на диске запись игрока 4001: ' + JSON.stringify(запись1) + ' (ждали причину «сам»)'
);

/* Сценарий 2: Telegram не доставил письмо — суточная пометка бота,
   по-прежнему может подождать. Проверяем это только на НЕиспорченной
   копии: смысл сценария — убедиться, что развилка не выродилась в
   «всё срочно», а не в том, что он должен провалиться при --сломать
   (порча трогает только ветку 'сам' — сценарий 2 на сломанной копии
   ничего нового не покажет). */
if (!СЛОМАТЬ) {
  const данные2 = запретитьВОтдельномПроцессе(путьКНеЗвать, 5002, 'ботНеПишет');

  проверить(
    'отказ «ботНеПишет» не пишется на диск немедленно — суточная пометка по-прежнему отложена',
    данные2 === null,
    'файл «не звать» появился сразу, хотя причина «ботНеПишет» должна была остаться в памяти: ' + JSON.stringify(данные2)
  );
}

console.log('');
let провалов = 0;
for (const п of ПРОВЕРКИ) {
  if (п.ошибка) {
    провалов++;
    console.log('  ПРОВАЛ ' + п.имя + ': ' + п.ошибка);
  } else {
    console.log('  ок     ' + п.имя);
  }
}
console.log('');
console.log('Итого проверок: ' + ПРОВЕРКИ.length + ', провалов: ' + провалов);
process.exit(провалов > 0 ? 1 : 0);
