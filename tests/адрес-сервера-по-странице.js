/* =====================================================================
   АДРЕС СЕРВЕРА ПО УМОЛЧАНИЮ — «ТОТ ЖЕ АДРЕС, ОТКУДА ПРИШЛА СТРАНИЦА».

   Переезд игры на собственный домен (https://igra.medart.com.ua) поменял
   правило запасного адреса: nginx там отдаёт и страницы, и сервер комнат
   с ОДНОГО адреса (страницы — как есть, «/что-нового», «/ход» и прочий
   API — дальше на 127.0.0.1:8790). Значит, если в ссылке нет «?сервер=»
   и руками ничего не вписано, честный запасной адрес для такой страницы —
   её же собственный origin, а не голая константа 127.0.0.1:8790.

   Свой компьютер (файл с диска или localhost/127.0.0.1/домашняя сеть) —
   это разработка, там подмена не нужна, там сервер и правда на 8790.

   Известные витрины без сервера (сейчас — GitHub Pages, хост «*.github.io»)
   из правила «origin» нарочно исключены: своего сервера там нет и не будет,
   а origin выглядит как настоящий рабочий адрес. На GitHub Pages это отловил
   ревьюер — лобби дурака там само стучалось на свой же «github.io/рейтинг»,
   получало 404 и потом врало «сервер держится на домашнем компьютере».
   Такой странице возвращаем честное «адреса нет» (пустую строку) — так же,
   как это было устроено до переезда на собственный домен.

   Проверяем три файла, которые умеют считать адрес сервера сами:
     А. js/сеть.js            — главный разбор (ссылка / вписан / запасной);
     Б. js/рейтинг-экран.js   — свой упрощённый разбор для страниц без
                                 js/сеть.js (шахматы, нарды);
     В. js/похвастаться.js    — свой упрощённый разбор для той же причины.
   На страницах, где js/сеть.js подключён, Б и В спрашивают адрес у него
   («одна правда») — это уже устроено раньше и здесь не проверяется заново;
   собственная копия у них — только запасной путь, и вот его правило
   должно совпадать с сеть.js.

   Как поднимаем файлы без браузера — tests/поддельный-браузер.js (секция А)
   и лёгкая ручная песочница vm, как в tests/проверка-похвастаться-сервер-
   и-сеть.js (секции Б и В: там window.Сеть либо не приходит вовсе, либо
   свой — «БезСети» путь проверяется в чистом виде).

   Запуск:            node tests/адрес-сервера-по-странице.js
   Ломающий запуск:    node tests/адрес-сервера-по-странице.js --сломать
     — копирует ВСЕ ТРИ файла во временную папку (fs.mkdtempSync в
       os.tmpdir(), НЕ в проект; путь при поломке печатается в консоль);
       в каждой копии проверку «это витрина без сервера» отключает
       (заменяет на условие, которое никогда не срабатывает), так что
       запасной адрес для github.io снова отдаёт origin вместо пустой
       строки. Все три секции (А, Б, В) в этом случае обязаны покраснеть
       ровно на новых кейсах «GitHub Pages». Строка для замены в каждом
       файле ищется дословно — не нашлась, значит файл изменился и порчу
       нужно переписать: скрипт в этом случае выходит с кодом 2, а не
       притворяется, что всё хорошо. Копии за собой прибираем.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
