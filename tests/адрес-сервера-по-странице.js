/* =======================================================================
   Секция Г: js/рейтинг-экран.js ВМЕСТЕ с js/сеть.js на одной странице —
   запрос обязан идти через window.Сеть.рейтингТаблица, а не отдельным
   fetch в обход Сети (правило «сеть.js — единственное место браузера,
   знающее сервер»). Оба файла делят одну песочницу, как на живой странице,
   где сеть.js подключён раньше рейтинг-экран.js (нарды.html, шашки.html).
   ======================================================================= */
function проверитьРейтингВместеССетью(исходникСети, исходникРейтинга, пометка) {
  function итог(п) {
    let вызововСети = 0;
    let вызововFetch = 0;
    const рез = поднять(исходникСети, {
      документ: сделатьДокумент(), память: сделатьПамять(false),
      telegram: { onEvent: function () {}, offEvent: function () {}, isActive: true },
      fetch: function () { вызововFetch += 1; return new Promise(function () {}); },
      размер: { ширина: 390, высота: 844 }, имяФайла: 'js/сеть.js'
    });
    рез.окно.location = п;
    // Рейтинг-экран.js — в ТОЙ ЖЕ песочнице: на живой странице он тоже
    // делит одно window с сеть.js.
    vm.runInContext(исходникРейтинга, рез.песочница, { filename: 'js/рейтинг-экран.js' });
    if (!рез.окно.Сеть || typeof рез.окно.Сеть.рейтингТаблица !== 'function') return null;
    // Дверь подменяем шпионом: считает вызовы и сам зависает — экран это
    // переживает так же, как обрыв связи (обещание просто не разрешится).
    рез.окно.Сеть.рейтингТаблица = function () {
      вызововСети += 1;
      return new Promise(function () {});
    };
    if (!рез.окно.ЭкранРейтинга) return null;
    рез.окно.ЭкранРейтинга.моёМесто('дурак');
    return { вызововСети: вызововСети, вызововFetch: вызововFetch };
  }

  const п = пометка ? '[' + пометка + '] ' : '';

  const дом = итог(место('https:', 'igra.medart.com.ua', 'https://igra.medart.com.ua'));
  проверить(Boolean(дом) && дом.вызововСети > 0,
    п + 'Г1 (рейтинг-экран + сеть.js): запрос идёт через window.Сеть.рейтингТаблица ' +
    '(вызовов двери: ' + JSON.stringify(дом && дом.вызововСети) + ')');
  проверить(Boolean(дом) && дом.вызововFetch === 0,
    п + 'Г2 (рейтинг-экран + сеть.js): экран не бьёт в fetch напрямую, в обход Сети ' +
    '(вызовов fetch: ' + JSON.stringify(дом && дом.вызововFetch) + ')');

  // Витрина без сервера (GitHub Pages) — дверь в window.Сеть всё равно
  // обязана быть позвана: диспетчер рейтинг-экрана решает по наличию
  // самой функции, а не по тому, чем поход на сервер закончится.
  const витрина = итог(место('https:', 'aleustim-boop.github.io', 'https://aleustim-boop.github.io'));
  проверить(Boolean(витрина) && витрина.вызововСети > 0,
    п + 'Г3 (рейтинг-экран + сеть.js, GitHub Pages без сервера): дверь всё равно позвана ' +
    '(вызовов двери: ' + JSON.stringify(витрина && витрина.вызововСети) + ')');
}

/* =======================================================================
   Секция Д: js/рейтинг-экран.js — видПоОтвету({ беда: 'запрет-браузера' })
   обязана вернуть свой случай, а не провалиться в дефолт. Требуем модуль
   напрямую (без window/vm) — так же, как это уже делает tests/рейтинг-
   экран-четыре-игры.js через тот же module.exports.видПоОтвету.
   ======================================================================= */
function проверитьВидЗапретБраузера(путьМодуля, пометка) {
  const п = пометка ? '[' + пометка + '] ' : '';
  delete require.cache[path.resolve(путьМодуля)];
  let модуль;
  try {
    модуль = require(path.resolve(путьМодуля));
  } catch (сбой) {
    проверить(false, п + 'Д (беда «запрет-браузера»): модуль ' + путьМодуля + ' не загрузился: ' + сбой.message);
    return;
  }
  if (typeof модуль.видПоОтвету !== 'function') {
    проверить(false, п + 'Д (беда «запрет-браузера»): видПоОтвету не экспортирована');
    return;
  }
  const вид = модуль.видПоОтвету({ беда: 'запрет-браузера', данные: null }, 'очки');
  проверить(Boolean(вид) && вид.случай === 'запрет-браузера',
    п + 'Д1: беда «запрет-браузера» получает свой случай, не дефолт (получили: ' +
    JSON.stringify(вид && вид.случай) + ')');
  проверить(Boolean(вид) && Boolean(вид.главное) && вид.главное !== 'Сервер с рейтингом не отвечает',
    п + 'Д2: текст «запрет-браузера» не совпадает с текстом «нет-связи» (получили: ' +
    JSON.stringify(вид && вид.главное) + ')');
  проверить(Boolean(вид) && /браузер/i.test(вид.пояснение || '') && /https/i.test(вид.пояснение || ''),
    п + 'Д3: пояснение честно называет причину (упоминает браузер и https)');
}

/* Порча для --сломать (секция Д): вырезаем ветку 'запрет-браузера' из
   копии решение() целиком — код обязан провалиться в соседнюю ветку
   'связь' и потерять свой случай. Метки ищутся дословно, как и в
   «испортитьВитрину»: код переписали — порчу переписывают тем же коммитом. */
const МЕТКА_ЗАПРЕТ_БРАУЗЕРА_НАЧАЛО =
  "    /* Игра открыта по https, а сервер вписан обычным http-адресом";
const МЕТКА_СВЯЗЬ_НАЧАЛО = "    if (итог.беда === 'связь') {";

function вырезатьВетку(исходник, путь, начало, конец) {
  const и1 = исходник.indexOf(начало);
  const и2 = исходник.indexOf(конец);
  if (и1 === -1 || и2 === -1 || и2 <= и1) {
    console.error('Порча не удалась: ветка «запрет-браузера» не найдена дословно в ' + путь +
      ' — код переписали, порчу для --сломать надо обновить под новый текст.');
    process.exit(2);
  }
  return исходник.slice(0, и1) + исходник.slice(и2);
}

/* ---------------------------------------------------------------------
   Строка порчи задаётся с обычным «\n» внутри, а искать её нужно и в
   CRLF-файлах (сеть.js, похвастаться.js), и в LF-файлах (рейтинг-экран.js):
   вид перевода строки — деталь конкретного файла, а не проверки. Поэтому
   каждый «\n» шаблона при поиске превращается в «\r?\n», остальной текст
   экранируется как обычная regex-строка.
   --------------------------------------------------------------------- */
function экранироватьRegex(текст) {
  return текст.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}
function построитьРегулярку(шаблон, флаги) {
  return new RegExp(шаблон.split('\n').map(экранироватьRegex).join('\\r?\\n'), флаги);
}
function переводСтрокФайла(исходник) {
  return исходник.indexOf('\r\n') !== -1 ? '\r\n' : '\n';
}
/* Вставляемый текст «стало» пишется с «\n» — здесь его переводы строк
   приводятся к тому же виду, каким хранится сам файл, чтобы копия не
   превратилась в мешанину CRLF и LF. */
function подПереводСтрокФайла(текст, исходник) {
  return текст.replace(/\r\n/g, '\n').split('\n').join(переводСтрокФайла(исходник));
}

/* ---------------------------------------------------------------------
   Порча для --сломать: в каждой копии проверка «это витрина без сервера»
   заменяется на условие, которое никогда не срабатывает, — запасной адрес
   для github.io снова отдаёт origin вместо пустой строки. Строка ищется
   дословно в каждом файле отдельно, независимо от вида перевода строки
   (CRLF или LF) — не нашлась ни в каком виде, значит файл переписали.
   --------------------------------------------------------------------- */
function испортитьВитрину(исходник, путь, было, стало) {
  const дляПроверки = построитьРегулярку(было, '');
  if (!дляПроверки.test(исходник)) {
    console.error('Порча не удалась: проверка витрины без сервера не найдена дословно в ' + путь +
      ' — код переписали, проверку --сломать надо обновить под новый текст.');
    process.exit(2);
  }
  const дляЗамены = построитьРегулярку(было, 'g');
  const сталоПодСтиль = подПереводСтрокФайла(стало, исходник);
  return исходник.replace(дляЗамены, function () { return сталоПодСтиль; });
}

function главное() {
  const исходникСети = fs.readFileSync(ПУТЬ_СЕТЬ, 'utf8');
  const исходникРейтинга = fs.readFileSync(ПУТЬ_РЕЙТИНГ, 'utf8');
  const исходникПохвастаться = fs.readFileSync(ПУТЬ_ПОХВАСТАТЬСЯ, 'utf8');

  if (!ломать) {
    проверитьСеть(исходникСети, '');
    проверитьРейтинг(исходникРейтинга, '');
    проверитьПохвастаться(исходникПохвастаться, '');
    проверитьРейтингВместеССетью(исходникСети, исходникРейтинга, '');
    проверитьВидЗапретБраузера(ПУТЬ_РЕЙТИНГ, '');
  } else {
    const временнаяПапка = fs.mkdtempSync(path.join(os.tmpdir(), 'адрес-сервера-по-странице-'));

    const испорченнаяСеть = испортитьВитрину(исходникСети, ПУТЬ_СЕТЬ,
      '      if (ВИТРИНА_БЕЗ_СЕРВЕРА.test(хост)) return \'\';\n',
      '      if (false) return \'\';   // испорчено проверкой --сломать\n');
    fs.writeFileSync(path.join(временнаяПапка, 'сеть.js'), испорченнаяСеть, 'utf8');

    const испорченныйРейтинг = испортитьВитрину(исходникРейтинга, ПУТЬ_РЕЙТИНГ,
      '      if (ВИТРИНА_БЕЗ_СЕРВЕРА_БЕЗ_СЕТИ.test(хост)) return \'\';\n',
      '      if (false) return \'\';   // испорчено проверкой --сломать\n');
    fs.writeFileSync(path.join(временнаяПапка, 'рейтинг-экран.js'), испорченныйРейтинг, 'utf8');

    /* Своя, отдельная порча поверх той же копии — секции Д нужна не
       испорченная витрина, а вырезанная ветка 'запрет-браузера'. */
    const путьКопииБезЗапрета = path.join(временнаяПапка, 'рейтинг-экран-без-запрета.js');
    const рейтингБезЗапрета = вырезатьВетку(исходникРейтинга, ПУТЬ_РЕЙТИНГ,
      МЕТКА_ЗАПРЕТ_БРАУЗЕРА_НАЧАЛО, МЕТКА_СВЯЗЬ_НАЧАЛО);
    fs.writeFileSync(путьКопииБезЗапрета, рейтингБезЗапрета, 'utf8');

    const испорченныйПохвастаться = испортитьВитрину(исходникПохвастаться, ПУТЬ_ПОХВАСТАТЬСЯ,
      '      if (ВИТРИНА_БЕЗ_СЕРВЕРА.test(хост)) return \'\';\n',
      '      if (false) return \'\';   // испорчено проверкой --сломать\n');
    fs.writeFileSync(path.join(временнаяПапка, 'похвастаться.js'), испорченныйПохвастаться, 'utf8');

    console.log('[--сломать] копии испорченных файлов: ' + временнаяПапка);
    проверитьСеть(испорченнаяСеть, '--сломать');
    проверитьРейтинг(испорченныйРейтинг, '--сломать');
    проверитьПохвастаться(испорченныйПохвастаться, '--сломать');
    проверитьРейтингВместеССетью(испорченнаяСеть, испорченныйРейтинг, '--сломать');
    проверитьВидЗапретБраузера(путьКопииБезЗапрета, '--сломать');

    try { fs.rmSync(временнаяПапка, { recursive: true, force: true }); }
    catch (e) { console.error('Не удалось убрать временную папку ' + временнаяПапка + ': ' + e); }
  }

  const провалы = проверки.filter(function (п) { return !п.ок; });
  console.log((ломать ? '[--сломать] ' : '') + 'Адрес сервера по умолчанию — по странице:');
  for (const п of проверки) console.log((п.ок ? '  ok   ' : '  ПРОВАЛ ') + п.текст);
  console.log('Итого проверок: ' + проверки.length + ', провалов: ' + провалы.length);
  process.exit(провалы.length ? 1 : 0);
}

главное();
