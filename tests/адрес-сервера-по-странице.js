const проверки = [];
function проверить(условие, текст) { проверки.push({ ок: Boolean(условие), текст: текст }); }

/* ---------------------------------------------------------------------
   Общий вид window.location для случая: место(протокол, хост, origin, поиск).
   --------------------------------------------------------------------- */
function место(протокол, хост, origin, поиск) {
  return { href: origin + '/', search: поиск || '', hash: '', pathname: '/', origin: origin, protocol: протокол, host: хост };
}

/* =======================================================================
   Секция А: js/сеть.js — четыре случая из задания плюс витрина без сервера.
   ======================================================================= */
function проверитьСеть(исходникСети, пометка) {
  function адресДляМеста(п) {
    const рез = поднять(исходникСети, {
      документ: сделатьДокумент(), память: сделатьПамять(false),
      telegram: { onEvent: function () {}, offEvent: function () {}, isActive: true },
      fetch: function () { return new Promise(function () {}); },
      размер: { ширина: 390, высота: 844 }, имяФайла: 'js/сеть.js'
    });
    рез.окно.location = п;
    return {
      адрес: rez_спросить(рез, 'window.Сеть.адрес()'),
      запасной: rez_спросить(рез, 'window.Сеть.запаснойАдрес()')
    };
  }
  function rez_спросить(рез, выражение) { return рез.спросить(выражение); }

  const п = пометка ? '[' + пометка + '] ' : '';

  // 1) настоящий домен без хвостика «?сервер=» → адрес страницы (origin).
  const дом = адресДляМеста(место('https:', 'igra.medart.com.ua', 'https://igra.medart.com.ua'));
  проверить(дом.адрес === 'https://igra.medart.com.ua',
    п + 'А1: https://igra.medart.com.ua/ без хвоста → адрес() === origin страницы ' +
    '(получили: ' + JSON.stringify(дом.адрес) + ')');
  проверить(дом.запасной === 'https://igra.medart.com.ua',
    п + 'А1б: та же страница → запаснойАдрес() === origin (получили: ' + JSON.stringify(дом.запасной) + ')');

  // 2) с «?сервер=X» → именно X, свой домен тут ни при чём.
  const сХвостом = адресДляМеста(
    место('https:', 'igra.medart.com.ua', 'https://igra.medart.com.ua',
      '?сервер=' + encodeURIComponent('https://мой-туннель.example')));
  проверить(сХвостом.адрес === 'https://мой-туннель.example',
    п + 'А2: ?сервер=https://мой-туннель.example → адрес() === хвостик ' +
    '(получили: ' + JSON.stringify(сХвостом.адрес) + ')');

  // 3) localhost (со своим портом страниц) → адрес разработки 127.0.0.1:8790.
  const локально = адресДляМеста(место('http:', 'localhost:8080', 'http://localhost:8080'));
  проверить(локально.адрес === 'http://127.0.0.1:8790',
    п + 'А3: localhost:8080 → адрес() === http://127.0.0.1:8790 ' +
    '(получили: ' + JSON.stringify(локально.адрес) + ')');

  // 4) файл с диска → тот же адрес разработки.
  const файл = адресДляМеста({ href: 'file:///D:/Claud/Games/index.html', search: '', hash: '',
    pathname: '/D:/Claud/Games/index.html', origin: 'null', protocol: 'file:', host: '' });
  проверить(файл.адрес === 'http://127.0.0.1:8790',
    п + 'А4: file:// → адрес() === http://127.0.0.1:8790 (получили: ' + JSON.stringify(файл.адрес) + ')');

  // 5) известная витрина без сервера (GitHub Pages) → честное «адреса нет»,
  //    а не origin: своего сервера там нет и не будет, и origin выглядел бы
  //    как настоящий рабочий адрес.
  const витрина = адресДляМеста(место('https:', 'aleustim-boop.github.io', 'https://aleustim-boop.github.io'));
  проверить(витрина.адрес === '',
    п + 'А5: https://aleustim-boop.github.io/ без хвоста → адрес() === \'\' ' +
    '(получили: ' + JSON.stringify(витрина.адрес) + ')');
  проверить(витрина.запасной === '',
    п + 'А5б: та же страница → запаснойАдрес() === \'\' (получили: ' + JSON.stringify(витрина.запасной) + ')');
}

/* =======================================================================
   Секция Б: js/рейтинг-экран.js без js/сеть.js на странице — «БезСети».
   Наблюдаем реальный адрес запроса через window.ЭкранРейтинга.моёМесто():
   внутренние функции разбора адреса файл наружу не выводит, а именно
   на этот адрес уходит fetch за витриной рейтинга.
   ======================================================================= */
function проверитьРейтинг(исходникРейтинга, пометка) {
  function путьЗапроса(п) {
    const пути = [];
    const рез = поднять(исходникРейтинга, {
      документ: сделатьДокумент(), память: сделатьПамять(false),
      fetch: function (url) { пути.push(String(url)); return new Promise(function () {}); },
      имяФайла: 'js/рейтинг-экран.js'
    });
    рез.окно.location = п;
    if (!рез.окно.ЭкранРейтинга) return null;
    рез.окно.ЭкранРейтинга.моёМесто('дурак');
    return пути[0] || null;
  }

  const п = пометка ? '[' + пометка + '] ' : '';

  const дом = путьЗапроса(место('https:', 'igra.medart.com.ua', 'https://igra.medart.com.ua'));
  проверить(дом === 'https://igra.medart.com.ua/рейтинг',
    п + 'Б1 (рейтинг-экран, без сети): настоящий домен без хвоста → запрос на origin страницы ' +
    '(получили: ' + JSON.stringify(дом) + ')');

  const локально = путьЗапроса(место('http:', 'localhost:8080', 'http://localhost:8080'));
  проверить(локально === 'http://127.0.0.1:8790/рейтинг',
    п + 'Б2 (рейтинг-экран, без сети): localhost:8080 → запрос на http://127.0.0.1:8790 ' +
    '(получили: ' + JSON.stringify(локально) + ')');

  const файл = путьЗапроса({ href: 'file:///D:/Claud/Games/index.html', search: '', hash: '',
    pathname: '/D:/Claud/Games/index.html', origin: 'null', protocol: 'file:', host: '' });
  проверить(файл === 'http://127.0.0.1:8790/рейтинг',
    п + 'Б3 (рейтинг-экран, без сети): file:// → запрос на http://127.0.0.1:8790 ' +
    '(получили: ' + JSON.stringify(файл) + ')');

  // 4) известная витрина без сервера (GitHub Pages) → адреса нет вовсе,
  //    и бедаАдреса('нет-адреса') обрывает дело раньше fetch: запроса
  //    на github.io/рейтинг быть не должно.
  const витрина = путьЗапроса(место('https:', 'aleustim-boop.github.io', 'https://aleustim-boop.github.io'));
  проверить(витрина === null,
    п + 'Б4 (рейтинг-экран, без сети): GitHub Pages без хвоста → адреса нет, запрос на сервер не уходит ' +
    '(получили: ' + JSON.stringify(витрина) + ')');
}

/* =======================================================================
   Секция В: js/похвастаться.js без js/сеть.js на странице — «БезСети».
   Наблюдаем адрес запроса через Сеть.похвастаться(...) с настройками,
   при которых дверь идёт путём «поверх» (единственный путь, где вообще
   стучимся на сервер) — тот же приём, что в tests/проверка-похвастаться-
   сервер-и-сеть.js.
   ======================================================================= */
function проверитьПохвастаться(исходникПохвастаться, пометка) {
  function путьЗапроса(п) {
    const тела = [];
    const памятьКарта = new Map();
    const памятьБраузера = {
      getItem: function (к) { return памятьКарта.has(к) ? памятьКарта.get(к) : null; },
      setItem: function (к, ч) { памятьКарта.set(к, String(ч)); },
      removeItem: function (к) { памятьКарта.delete(к); }
    };
    const окно = {
      location: п, localStorage: памятьБраузера, sessionStorage: памятьБраузера,
      addEventListener: function () {},
      navigator: { clipboard: { writeText: function () { return Promise.resolve(); } } },
      Telegram: { WebApp: {
        initData: 'user=%7B%22id%22%3A1%7D&hash=abc', platform: 'android',
        isVersionAtLeast: function () { return true; },
        shareMessage: function (номер, готово) { готово(true); },
        openTelegramLink: function () {}
      } }
    };
    const страница = { getElementById: function () { return null; }, addEventListener: function () {},
      querySelectorAll: function () { return []; }, readyState: 'complete' };
    const окружение = {
      window: окно, document: страница, console: { log: function () {}, warn: function () {}, error: function () {} },
      fetch: function (адрес) { тела.push(String(адрес)); return new Promise(function () {}); },
      setTimeout: setTimeout, clearTimeout: clearTimeout, setInterval: setInterval, clearInterval: clearInterval,
      URLSearchParams: URLSearchParams, URL: URL, AbortController: AbortController,
      Promise: Promise, JSON: JSON, Date: Date, Math: Math
    };
    окружение.globalThis = окружение;
    vm.runInNewContext(исходникПохвастаться, окружение, { filename: 'js/похвастаться.js' });
    окно.Сеть.похвастаться({ игра: 'дурак', исход: 'победа' });
    return тела[0] || null;
  }

  const п = пометка ? '[' + пометка + '] ' : '';

  const дом = путьЗапроса(место('https:', 'igra.medart.com.ua', 'https://igra.medart.com.ua'));
  проверить(дом && дом.indexOf('https://igra.medart.com.ua/') === 0,
    п + 'В1 (похвастаться, без сети): настоящий домен без хвоста → запрос на origin страницы ' +
    '(получили: ' + JSON.stringify(дом) + ')');

  const локально = путьЗапроса(место('http:', 'localhost:8080', 'http://localhost:8080'));
  проверить(локально && локально.indexOf('http://127.0.0.1:8790/') === 0,
    п + 'В2 (похвастаться, без сети): localhost:8080 → запрос на http://127.0.0.1:8790 ' +
    '(получили: ' + JSON.stringify(локально) + ')');

  const файл = путьЗапроса({ href: 'file:///D:/Claud/Games/index.html', search: '', hash: '',
    pathname: '/D:/Claud/Games/index.html', origin: 'null', protocol: 'file:', host: '' });
  проверить(файл && файл.indexOf('http://127.0.0.1:8790/') === 0,
    п + 'В3 (похвастаться, без сети): file:// → запрос на http://127.0.0.1:8790 ' +
    '(получили: ' + JSON.stringify(файл) + ')');

  // 4) известная витрина без сервера (GitHub Pages) → адресСервера() === '',
  //    и путь запроса остаётся голым «/приглашение» — без происхождения
  //    github.io. Функция «запрос» стучится всегда (это не меняем), но
  //    честное «адреса нет» не даёт ей стучаться именно в github.io.
  const витрина = путьЗапроса(место('https:', 'aleustim-boop.github.io', 'https://aleustim-boop.github.io'));
  проверить(витрина === '/приглашение',
    п + 'В4 (похвастаться, без сети): GitHub Pages без хвоста → адреса нет: путь запроса остаётся ' +
    'относительным, без происхождения github.io (получили: ' + JSON.stringify(витрина) + ')');
}

/* ---------------------------------------------------------------------
   Порча для --сломать: в каждой копии проверка «это витрина без сервера»
   заменяется на условие, которое никогда не срабатывает, — запасной адрес
   для github.io снова отдаёт origin вместо пустой строки. Строка ищется
   дословно в каждом файле отдельно (у сеть.js — CRLF, у остальных — LF).
   --------------------------------------------------------------------- */
function испортитьВитрину(исходник, путь, было, стало) {
  if (исходник.indexOf(было) === -1) {
    console.error('Порча не удалась: проверка витрины без сервера не найдена дословно в ' + путь +
      ' — код переписали, проверку --сломать надо обновить под новый текст.');
    process.exit(2);
  }
  return исходник.split(было).join(стало);
}

function главное() {
  const исходникСети = fs.readFileSync(ПУТЬ_СЕТЬ, 'utf8');
  const исходникРейтинга = fs.readFileSync(ПУТЬ_РЕЙТИНГ, 'utf8');
  const исходникПохвастаться = fs.readFileSync(ПУТЬ_ПОХВАСТАТЬСЯ, 'utf8');

  if (!ломать) {
    проверитьСеть(исходникСети, '');
    проверитьРейтинг(исходникРейтинга, '');
    проверитьПохвастаться(исходникПохвастаться, '');
  } else {
    const временнаяПапка = fs.mkdtempSync(path.join(os.tmpdir(), 'адрес-сервера-по-странице-'));

    const испорченнаяСеть = испортитьВитрину(исходникСети, ПУТЬ_СЕТЬ,
      '      if (ВИТРИНА_БЕЗ_СЕРВЕРА.test(хост)) return \'\';\r\n',
      '      if (false) return \'\';   // испорчено проверкой --сломать\r\n');
    fs.writeFileSync(path.join(временнаяПапка, 'сеть.js'), испорченнаяСеть, 'utf8');

    const испорченныйРейтинг = испортитьВитрину(исходникРейтинга, ПУТЬ_РЕЙТИНГ,
      '      if (ВИТРИНА_БЕЗ_СЕРВЕРА_БЕЗ_СЕТИ.test(хост)) return \'\';\n',
      '      if (false) return \'\';   // испорчено проверкой --сломать\n');
    fs.writeFileSync(path.join(временнаяПапка, 'рейтинг-экран.js'), испорченныйРейтинг, 'utf8');

    const испорченныйПохвастаться = испортитьВитрину(исходникПохвастаться, ПУТЬ_ПОХВАСТАТЬСЯ,
      '      if (ВИТРИНА_БЕЗ_СЕРВЕРА.test(хост)) return \'\';\n',
      '      if (false) return \'\';   // испорчено проверкой --сломать\n');
    fs.writeFileSync(path.join(временнаяПапка, 'похвастаться.js'), испорченныйПохвастаться, 'utf8');

    console.log('[--сломать] копии испорченных файлов: ' + временнаяПапка);
    проверитьСеть(испорченнаяСеть, '--сломать');
    проверитьРейтинг(испорченныйРейтинг, '--сломать');
    проверитьПохвастаться(испорченныйПохвастаться, '--сломать');

    try { fs.rmSync(временнаяПапка, { recursive: true, force: true }); }
    catch (e) { console.error('Не удалось убрать временную папку ' + временнаяПапка + ': ' + e); }
  }

  const провалы = проверки.filter(function (п) { return !п.ок; });
  console.log((ломать ? '[--сломать] ' : '') + 'Адрес сервера по умолчанию — по странице:');
  for (const п of проверки) console.log((п.ок ? '  ok   ' : '  ПРОВАЛ ') + п.текст);
  console.log('Итого проверок: ' + проверки.length + ', провалов: ' + провалы.length);
  process.exit(провалы.length ? 1 : 0);
}

главное();
