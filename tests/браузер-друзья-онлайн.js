function постучать(адрес) {
  return new Promise((готово) => {
    const з = http.get(адрес, (о) => { о.resume(); готово(о.statusCode); });
    з.on('error', () => готово(0));
    з.setTimeout(1500, () => { з.destroy(); готово(0); });
  });
}
async function дождатьсяСтраниц() {
  for (let п = 0; п < 40; п++) {
    if (await постучать(АДРЕС_СТРАНИЦ + '/index.html')) return true;
    await пауза(150);
  }
  return false;
}

function следитьЗаКонсолью(страница, красные) {
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const текст = м.text();
    const откуда = (м.location && м.location() && м.location().url) || '';
    const вместе = текст + ' ' + откуда;
    if (/telegram-web-app\.js|telegram\.org/.test(вместе)) return;
    // Сценарии «6. Обрывы/429» и «2. Отказ /прятаться» нарочно портят ответ
    // наших же подделанных дверей — Chromium сам пишет об этом красным,
    // это след подделки, не поломка игры.
    if (/(друзья-онлайн|%D0%B4%D1%80%D1%83%D0%B7%D1%8C%D1%8F-%D0%BE%D0%BD%D0%BB%D0%B0%D0%B9%D0%BD)/.test(вместе) &&
        (/ERR_FAILED/.test(вместе) || /status of 429/.test(вместе))) return;
    if (/(прятаться|%D0%BF%D1%80%D1%8F%D1%82%D0%B0%D1%82%D1%8C%D1%81%D1%8F)/.test(вместе) && /status of 400/.test(вместе)) return;
    красные.push('консоль: ' + текст + (откуда ? ' (' + откуда + ')' : ''));
  });
}

