async function случайОдноМесто() {
  console.log('\n(а) Один аккаунт с двух устройств — одно место');
  const хозяин = await создать(7001, 'metka-hozyain-0001', { игра: 'дурак', мест: 3 });
  проверить('(а) комната на троих создана', хозяин.номер === 200 && хозяин.данные.код,
    JSON.stringify(хозяин.данные));
  const код = хозяин.данные.код;

  const телефон = await войти(код, 7002, 'metka-telefon-0001');
  проверить('(а) первое устройство вошло', телефон.номер === 200, JSON.stringify(телефон.данные));
  const компьютер = await войти(код, 7002, 'metka-kompyuter-0001');
  проверить('(а) второе устройство того же аккаунта вошло', компьютер.номер === 200,
    JSON.stringify(компьютер.данные));

  const комната = комнатаПо(код, хозяин.данные.пропуск);
  проверить('(а) комната нашлась по пропуску хозяина', Boolean(комната));
  if (!комната) return;
  const занято = Object.keys(комната.игроки).length;
  проверить('(а) за столом двое, а не трое', занято === 2, 'занято мест: ' + занято);
  проверить('(а) у аккаунта 7002 ровно одно место', местУНомера(комната, 7002) === 1,
    'мест: ' + местУНомера(комната, 7002));
  проверить('(а) второе устройство получило другой пропуск',
    компьютер.данные.пропуск && компьютер.данные.пропуск !== телефон.данные.пропуск);

  const второйЖив = await состояние(код, компьютер.данные.пропуск);
  проверить('(а) пропуск второго устройства рабочий', второйЖив.номер === 200,
    'код ответа ' + второйЖив.номер);
  const первыйЖив = await состояние(код, телефон.данные.пропуск);
  проверить('(а) пропуск первого устройства больше не действует', первыйЖив.номер !== 200,
    'код ответа ' + первыйЖив.номер);
  проверить('(а) комната помнит, что первый пропуск сменён (для слов «с другого устройства»)',
    typeof комнаты.пропускСменён === 'function' && комнаты.пропускСменён(код, телефон.данные.пропуск) === true);
  проверить('(а) чужой пропуск сменённым не считается',
    typeof комнаты.пропускСменён === 'function' && комнаты.пропускСменён(код, 'нет-такого-пропуска') === false);

  // Хозяин со второго устройства тоже возвращается на своё место.
  const хозяинПК = await войти(код, 7001, 'metka-hozyain-pk-0001');
  проверить('(а) хозяин со второго устройства вошёл', хозяинПК.номер === 200, JSON.stringify(хозяинПК.данные));
  проверить('(а) после этого за столом всё ещё двое', Object.keys(комната.игроки).length === 2,
    'занято мест: ' + Object.keys(комната.игроки).length);

  // Третье место по-прежнему свободно для настоящего третьего человека.
  const третий = await войти(код, 7003, 'metka-tretiy-0001');
  проверить('(а) другой аккаунт садится на свободное третье место', третий.номер === 200,
    JSON.stringify(третий.данные));
  проверить('(а) теперь за столом трое', Object.keys(комната.игроки).length === 3);

  // Повтор с той же страницы (та же метка) — прежний пропуск, никого не выбивает.
  const повтор = await войти(код, 7003, 'metka-tretiy-0001');
  проверить('(а) повтор с той же метки отдаёт тот же пропуск',
    повтор.номер === 200 && повтор.данные.пропуск === третий.данные.пропуск);
}

