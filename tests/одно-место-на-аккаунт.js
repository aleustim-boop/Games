function пауза(мс) {
  return new Promise(function (готово) { setTimeout(готово, мс); });
}

/**
 * Ждём, пока запрос действительно встанет в очередь длинного опроса
 * (комната.ждущие) — иначе следующий шаг подменил бы пропуск раньше, чем
 * сервер успел бы его прочитать, и опрос упал бы в другую, уже рабочую
 * ветку (узнатьИгрока сразу увидел бы негодный пропуск).
 */
async function дождатьсяОжидающего(комната, ктоЯ, потолокМс) {
  const до = Date.now() + потолокМс;
  while (Date.now() < до) {
    if (комната.ждущие.some(function (ж) { return ж.ктоЯ === ктоЯ; })) return true;
    await пауза(5);
  }
  return false;
}

async function случайЧтоНовогоПриСмене() {
  console.log('\n(к) «Что нового» при смене пропуска — признак и в 200-ответе');

  /* Короткий опрос нужен только этому случаю, чтобы не ждать боевые
     25 секунд. Длительность опроса — одна переменная на весь процесс
     (server/сервер.js), её меняет только запустить(); поднимаем ради
     этого одноразовый сервер на отдельном порту и тут же гасим — сам
     он ни одного запроса не примет, нужен только побочный эффект. */
  const временный = сервера.запустить(ПОРТ_ВРЕМЕННОГО, 300);
  await new Promise(function (готово) { временный.close(готово); });

  const хозяин = await создать(7901, 'metka-chto-hoz-0001', { игра: 'дурак', мест: 3 });
  const код = хозяин.данные.код;
  const устройствоА = await войти(код, 7902, 'metka-chto-a-00001');
  проверить('(к) устройство А вошло', устройствоА.номер === 200, JSON.stringify(устройствоА.данные));
  const найденоА = комнаты.найтиИгрока(код, устройствоА.данные.пропуск);
  проверить('(к) устройство А нашлось в комнате', Boolean(найденоА));
  if (!найденоА) return;
  const старыйПропуск = устройствоА.данные.пропуск;

  // Начинаем долгий опрос той же версией — сервер должен встать в ждущие
  // и ответить только по смене пропуска или по истечении срока.
  const долгийОпрос = запрос('/что-нового', { код: код, пропуск: старыйПропуск, версия: найденоА.комната.версия });
  const встал = await дождатьсяОжидающего(найденоА.комната, найденоА.ктоЯ, 2000);
  проверить('(к) опрос устройства А встал в ждущие', встал);

  /* Подменяем пропуск места напрямую в комнате — так же, как это в итоге
     делает вернутьУчастника при входе устройства Б, но БЕЗ разбудить():
     опрос А не должен проснуться сразу «изменилось», а обязан дождаться
     срока и распознать смену пропуска сам — это и есть развилка, которую
     чинит сервер.js (около строки 733). */
  найденоА.комната.игроки[найденоА.ктоЯ].пропуск = 'metka-b-podmena-propuska';
  if (!найденоА.комната.сменённыеПропуска) найденоА.комната.сменённыеПропуска = new Map();
  найденоА.комната.сменённыеПропуска.set(старыйПропуск, Date.now());

  const ответ = await долгийОпрос;
  проверить('(к) долгий опрос ответил 200', ответ.номер === 200, 'код ответа ' + ответ.номер);
  проверить('(к) долгий опрос сообщает «комнаты нет»', ответ.данные.комнатыНет === true, JSON.stringify(ответ.данные));
  проверить('(к) долгий опрос несёт признак пропускСменён', ответ.данные.пропускСменён === true,
    JSON.stringify(ответ.данные));
  проверить('(к) слово об ошибке то же, что и у 404 узнатьИгрока',
    ответ.данные.ошибка === 'Вы вошли с другого устройства', JSON.stringify(ответ.данные));

  // Чужой кривой (никогда не выданный) пропуск признака получать не должен.
  const чужойКривой = await запрос('/что-нового', { код: код, пропуск: 'нет-такого-пропуска-совсем' });
  проверить('(к) с чужим кривым пропуском признака смены нет',
    чужойКривой.данные.пропускСменён === undefined, JSON.stringify(чужойКривой.данные));
}

