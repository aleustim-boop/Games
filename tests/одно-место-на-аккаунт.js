/* -------------------------------------------------------------------
   Запросы и подпись Telegram (тот же приём, что в рейтинг-повтор-партии.js)
   ------------------------------------------------------------------- */

function запрос(путь, тело) {
  return new Promise(function (готово) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const req = http.request({
      host: '127.0.0.1', port: ПОРТ, method: 'POST', path: encodeURI(путь),
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let куски = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (к) { куски += к; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(куски); } catch (е) { разобрано = { сырое: куски }; }
        готово({ номер: ответ.statusCode, данные: разобрано });
      });
    });
    req.on('error', function (е) { готово({ номер: 0, данные: { ошибка: String(е.message) } }); });
    req.write(данные);
    req.end();
  });
}

function подписать(поля) {
  const строки = Object.keys(поля).map(function (к) { return к + '=' + поля[к]; }).sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(ТОКЕН).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}

function initDataДля(номер) {
  const поля = {
    query_id: 'AAОдноМесто' + номер,
    user: JSON.stringify({ id: номер, first_name: 'Игрок' + номер }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  поля.hash = подписать(поля);
  return Object.keys(поля)
    .map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(поля[к]); })
    .join('&');
}

function создать(номер, метка, доп) {
  return запрос('/создать', Object.assign({ имя: 'Х' + номер, метка: метка, initData: initDataДля(номер) }, доп));
}

function войти(код, номер, метка) {
  return запрос('/войти', { код: код, имя: 'Г' + номер, метка: метка, initData: initDataДля(номер) });
}

function состояние(код, пропуск) {
  return запрос('/состояние', { код: код, пропуск: пропуск });
}

/** Сколько мест за столом занимает человек с этим номером (смотрим саму комнату). */
function местУНомера(комната, номер) {
  return Object.keys(комната.игроки).filter(function (место) {
    const игрок = комната.игроки[место];
    return игрок && игрок.телеграм === номер;
  }).length;
}

function комнатаПо(код, пропуск) {
  const найдено = комнаты.найтиИгрока(код, пропуск);
  return найдено ? найдено.комната : null;
}

