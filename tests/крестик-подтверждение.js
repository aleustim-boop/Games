/*
 * Проверка: крестик в шапке Telegram больше не закрывает игру без вопроса.
 *
 * Сторожит четыре двери в js/telegram.js — спрашиватьПриЗакрытии() и
 * неСпрашиватьПриЗакрытии() (родные enableClosingConfirmation /
 * disableClosingConfirmation у Telegram) — и то, что подключение общее
 * для index.html, шашки.html, шахматы.html и нарды.html.
 *
 * Обычный прогон:   node tests/крестик-подтверждение.js
 * Ломающий прогон:   node tests/крестик-подтверждение.js --сломать
 *   (портит ВРЕМЕННУЮ копию файла, файлы игры не трогает,
 *    и требует, чтобы нужные проверки покраснели)
 *
 * Без браузера и без библиотек: структурные проверки читают текст файла,
 * живые прогоны (пункты 5 и 6) поднимают файл целиком в песочнице vm
 * с самодельными window/document — Node это умеет из коробки.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const os = require('os');
const vm = require('vm');

const КОРЕНЬ = path.resolve(__dirname, '..');
const ПУТЬ_TELEGRAM = path.join(КОРЕНЬ, 'js', 'telegram.js');
const СТРАНИЦЫ = ['index.html', 'шашки.html', 'шахматы.html', 'нарды.html'];

// ---------------------------------------------------------------------------
// Разбор текста: находим тело функции/объекта по фигурным скобкам,
// а не жадным regex'ом — иначе первая же вложенная функция обрежет кусок
// раньше времени. Строки и комментарии пропускаем, чтобы «}» внутри
// текста комментария не сбила счёт.
// ---------------------------------------------------------------------------

/** Бросаем это, когда проверка не смогла разобрать код — считаем её проваленной, а не «пропущенной». */
class ПроваленаПроверка extends Error {}

function найтиПарнуюСкобку(текст, откудаОткрывающая) {
  let глубина = 0;
  for (let i = откудаОткрывающая; i < текст.length; i++) {
    const символ = текст[i];
    const два = текст.slice(i, i + 2);

    if (два === '//') {
      const конецСтроки = текст.indexOf('\n', i);
      i = конецСтроки === -1 ? текст.length : конецСтроки;
      continue;
    }
    if (два === '/*') {
      const конецБлока = текст.indexOf('*/', i + 2);
      i = конецБлока === -1 ? текст.length : конецБлока + 1;
      continue;
    }
    if (символ === "'" || символ === '"' || символ === '`') {
      const кавычка = символ;
      i++;
      while (i < текст.length && текст[i] !== кавычка) {
        if (текст[i] === '\\') i++;
        i++;
      }
      continue;
    }
    if (символ === '{') глубина++;
    else if (символ === '}') {
      глубина--;
      if (глубина === 0) return i;
    }
  }
  throw new ПроваленаПроверка('скобки не сошлись — файл повреждён сильнее, чем ожидалось');
}

/** Текст тела "function имя(...) { ... }" вместе со скобками. */
function телоФункции(текст, имяФункции) {
  const метка = 'function ' + имяФункции;
  const начало = текст.indexOf(метка);
  if (начало === -1) {
    throw new ПроваленаПроверка('не нашёл "' + метка + '" в файле — функция пропала или переименована');
  }
  const открывающая = текст.indexOf('{', начало);
  if (открывающая === -1) throw new ПроваленаПроверка('у "' + имяФункции + '" не нашёл открывающую скобку');
  const конец = найтиПарнуюСкобку(текст, открывающая);
  return текст.slice(открывающая, конец + 1);
}

/** Текст тела объектного литерала вида "начало = { ... }". */
function телоОбъекта(текст, началоВыражения) {
  const начало = текст.indexOf(началоВыражения);
  if (начало === -1) throw new ПроваленаПроверка('не нашёл "' + началоВыражения + '" в файле');
  const открывающая = текст.indexOf('{', начало);
  if (открывающая === -1) throw new ПроваленаПроверка('после "' + началоВыражения + '" не нашёл "{"');
  const конец = найтиПарнуюСкобку(текст, открывающая);
  return текст.slice(открывающая, конец + 1);
}

// ---------------------------------------------------------------------------
// Живой прогон в песочнице vm (без браузера, без npm)
// ---------------------------------------------------------------------------

/*
 * document подставляем ПУСТЫМ объектом, а не оставляем неопределённым.
 * Разбор кода показал: применитьТема() читает "document.documentElement"
 * НАПРЯМУЮ (без typeof), и защищает её только то, что "!приложение"
 * стоит слева от || и обрывает проверку по короткому замыканию. Внутри
 * подключитьсяКTelegram приложение уже проверено на istina — короткое
 * замыкание не спасает, и без document в песочнице сценарий 6 падал бы
 * с "ReferenceError: document is not defined". Пустой объект чинит это,
 * не пряча большего: documentElement всё равно undefined, и все места,
 * которые проверяют его через typeof-защищённый корневойУзел(), тихо
 * возвращают null, как и должны в проверке без разметки.
 */
function запуститьВПесочнице(текстTelegram, подставкаTelegram) {
  const window = {
    addEventListener: function () {},
    removeEventListener: function () {}
  };
  if (подставкаTelegram) window.Telegram = { WebApp: подставкаTelegram };

  const песочница = {
    window: window,
    document: {},
    console: console,
    setTimeout: setTimeout,
    clearTimeout: clearTimeout
  };
  vm.createContext(песочница);
  vm.runInContext(текстTelegram, песочница, { filename: 'js/telegram.js (песочница проверки)' });
  return песочница.window;
}

// ---------------------------------------------------------------------------
// Сами проверки — принимают текст файла и версии страниц, отдают список результатов
// ---------------------------------------------------------------------------

function прочитатьВерсииСтраниц() {
  const версии = {};
  СТРАНИЦЫ.forEach(function (имяФайла) {
    const текст = fs.readFileSync(path.join(КОРЕНЬ, имяФайла), 'utf8');
    const совпадение = текст.match(/<script\s+src=["']js\/telegram\.js\?v=([^"']+)["']/);
    версии[имяФайла] = совпадение ? совпадение[1] : null;
  });
  return версии;
}

function проверитьВсё(текстTelegram, версииСтраниц) {
  const результаты = [];

  function добавить(имя, дело) {
    try {
      const подробности = дело();
      результаты.push({ имя: имя, ок: true, подробности: подробности || 'да' });
    } catch (ошибка) {
      результаты.push({ имя: имя, ок: false, подробности: ошибка.message });
    }
  }

  // 1. Обе двери определены и обе выставлены наружу в window.Телеграм
  добавить('1. обе двери есть и выставлены в window.Телеграм', function () {
    телоФункции(текстTelegram, 'спрашиватьПриЗакрытии');
    телоФункции(текстTelegram, 'неСпрашиватьПриЗакрытии');
    const блок = телоОбъекта(текстTelegram, 'window.Телеграм = {');
    if (!/спрашиватьПриЗакрытии\s*:\s*спрашиватьПриЗакрытии/.test(блок)) {
      throw new ПроваленаПроверка('window.Телеграм не отдаёт наружу спрашиватьПриЗакрытии');
    }
    if (!/неСпрашиватьПриЗакрытии\s*:\s*неСпрашиватьПриЗакрытии/.test(блок)) {
      throw new ПроваленаПроверка('window.Телеграм не отдаёт наружу неСпрашиватьПриЗакрытии');
    }
    return 'обе двери на месте и обе в window.Телеграм';
  });

  // 2. Включение вызывается внутри подключитьсяКTelegram, а не где-то запасном
  добавить('2. спрашиватьПриЗакрытии() вызывается внутри подключитьсяКTelegram', function () {
    const тело = телоФункции(текстTelegram, 'подключитьсяКTelegram');
    const местоВызова = тело.search(/спрашиватьПриЗакрытии\s*\(\s*\)\s*;/);
    if (местоВызова === -1) {
      throw new ПроваленаПроверка('внутри подключитьсяКTelegram нет вызова спрашиватьПриЗакрытии() — совпадений: 0');
    }
    const последнийReturnTrue = тело.lastIndexOf('return true');
    if (последнийReturnTrue === -1 || местоВызова > последнийReturnTrue) {
      throw new ПроваленаПроверка('вызов стоит после финального "return true" — до него можно не дойти');
    }
    return 'вызов найден до return true, дойти до него всегда можно';
  });

  // 3. Каждый вызов метода Telegram защищён typeof и try/catch
  добавить('3. enableClosingConfirmation/disableClosingConfirmation под typeof и try/catch', function () {
    [
      ['спрашиватьПриЗакрытии', 'enableClosingConfirmation'],
      ['неСпрашиватьПриЗакрытии', 'disableClosingConfirmation']
    ].forEach(function (пара) {
      const имяДвери = пара[0];
      const имяМетода = пара[1];
      const тело = телоФункции(текстTelegram, имяДвери);
      const iTry = тело.indexOf('try');
      const iTypeof = тело.indexOf("typeof приложение." + имяМетода + " === 'function'");
      const iВызов = тело.indexOf('приложение.' + имяМетода + '()');
      const iCatch = тело.indexOf('catch');
      if (iTry === -1 || iTypeof === -1 || iВызов === -1 || iCatch === -1) {
        throw new ПроваленаПроверка('в "' + имяДвери + '" не нашёл try/typeof/вызов/catch для ' + имяМетода + ' (совпадений может быть 0)');
      }
      if (!(iTry < iTypeof && iTypeof < iВызов && iВызов < iCatch)) {
        throw new ПроваленаПроверка('в "' + имяДвери + '" порядок try → typeof → вызов → catch нарушен для ' + имяМетода);
      }
    });
    return 'обе двери защищены как положено';
  });

  // 4. Все четыре страницы просят js/telegram.js с ОДНИМ номером ?v=
  добавить('4. index/шашки/шахматы/нарды подключают js/telegram.js с одинаковым ?v=', function () {
    const номера = {};
    СТРАНИЦЫ.forEach(function (имяФайла) {
      const версия = версииСтраниц[имяФайла];
      if (!версия) throw new ПроваленаПроверка(имяФайла + ' не подключает js/telegram.js?v=... вовсе (совпадений: 0)');
      номера[имяФайла] = версия;
    });
    const значения = Object.keys(номера).map(function (к) { return номера[к]; });
    const разъехались = значения.some(function (в) { return в !== значения[0]; });
    if (разъехались) throw new ПроваленаПроверка('номера ?v= разъехались: ' + JSON.stringify(номера));
    return 'у всех четырёх ?v=' + значения[0];
  });

  // 5. Живой прогон БЕЗ Telegram — не падает, дверь честно отвечает «нет»
  добавить('5. без Telegram файл подключается без исключений, дверь отвечает false', function () {
    const окно = запуститьВПесочнице(текстTelegram, null);
    if (!окно.Телеграм || typeof окно.Телеграм.спрашиватьПриЗакрытии !== 'function') {
      throw new ПроваленаПроверка('window.Телеграм.спрашиватьПриЗакрытии не появился в песочнице');
    }
    const ответ = окно.Телеграм.спрашиватьПриЗакрытии();
    if (ответ !== false) {
      throw new ПроваленаПроверка('без Telegram спрашиватьПриЗакрытии() вернул ' + JSON.stringify(ответ) + ', а не false');
    }
    return 'подключился без исключений, дверь вернула false';
  });

  // 6. Живой прогон С Telegram — метод РЕАЛЬНО позвали сам, без ручного вызова двери
  добавить('6. с Telegram enableClosingConfirmation вызывается сам при подключении', function () {
    let позвали = 0;
    запуститьВПесочнице(текстTelegram, { enableClosingConfirmation: function () { позвали++; } });
    if (позвали !== 1) {
      throw new ПроваленаПроверка('enableClosingConfirmation позвали ' + позвали + ' раз(а) при подключении файла, ожидали 1');
    }
    return 'файл сам позвал enableClosingConfirmation при подключении';
  });

  return результаты;
}

function напечатать(результаты, заголовок) {
  console.log('== ' + заголовок + ' ==');
  let ок = 0;
  результаты.forEach(function (р) {
    console.log((р.ок ? 'ОК    ' : 'ОШИБКА') + '  ' + р.имя + ' — ' + р.подробности);
    if (р.ок) ок++;
  });
  console.log('Итого: ' + ок + '/' + результаты.length + ' проверок в порядке');
  return ок === результаты.length;
}

// ---------------------------------------------------------------------------
// Обычный прогон
// ---------------------------------------------------------------------------

function обычныйПрогон() {
  const текст = fs.readFileSync(ПУТЬ_TELEGRAM, 'utf8');
  const версии = прочитатьВерсииСтраниц();
  const результаты = проверитьВсё(текст, версии);
  const всёХорошо = напечатать(результаты, 'js/telegram.js: подтверждение при закрытии крестиком');
  process.exit(всёХорошо ? 0 : 1);
}

// ---------------------------------------------------------------------------
// Ломающий прогон: портим ВРЕМЕННУЮ копию, файлы игры не трогаем
// ---------------------------------------------------------------------------

function ломающийПрогон() {
  const исходныйТекст = fs.readFileSync(ПУТЬ_TELEGRAM, 'utf8');

  // Ровно та поломка, из-за которой владелец снова вылетал бы из Telegram:
  // убираем вызов двери из подключитьсяКTelegram, оставляя саму дверь на месте.
  // Файл на CRLF (\r\n) — учитываем необязательный \r, иначе regex молча
  // не найдёт строку и решит, что портить нечего (см. ловушку "\b и кириллица":
  // здесь та же беда — тихий ноль совпадений, а не явная ошибка).
  const испорченныйТекст = исходныйТекст.replace(/\r?\n[ \t]*спрашиватьПриЗакрытии\(\);[ \t]*\r?\n/, '\n');
  if (испорченныйТекст === исходныйТекст) {
    console.error('ОШИБКА ЛОМАЮЩЕГО ЗАПУСКА: не нашёл строку с вызовом спрашиватьПриЗакрытии() внутри файла — портить нечего, сам ломающий запуск сломан');
    process.exit(1);
    return;
  }

  const временнаяПапка = fs.mkdtempSync(path.join(os.tmpdir(), 'крестик-подтверждение-'));
  const временныйФайл = path.join(временнаяПапка, 'telegram.js');
  fs.writeFileSync(временныйФайл, испорченныйТекст, 'utf8');

  try {
    const испорченныйИзФайла = fs.readFileSync(временныйФайл, 'utf8');
    const версии = прочитатьВерсииСтраниц(); // html эта поломка не трогает
    const результаты = проверитьВсё(испорченныйИзФайла, версии);

    console.log('== Ломающий запуск: убрали вызов спрашиватьПриЗакрытии() из подключитьсяКTelegram (временная копия: ' + временныйФайл + ') ==');
    результаты.forEach(function (р) {
      console.log((р.ок ? 'ОК    ' : 'ОШИБКА') + '  ' + р.имя + ' — ' + р.подробности);
    });

    // Эта поломка обязана уронить именно проверки №2 и №6 — они и сторожат
    // ровно то, что мы сломали. Если хоть одна осталась «ОК» — она слепая.
    const цели = [
      '2. спрашиватьПриЗакрытии() вызывается внутри подключитьсяКTelegram',
      '6. с Telegram enableClosingConfirmation вызывается сам при подключении'
    ];
    const слепые = результаты.filter(function (р) { return цели.indexOf(р.имя) !== -1 && р.ок; });

    if (слепые.length > 0) {
      console.error('ЛОМАЮЩИЙ ЗАПУСК ПРОВАЛЕН: порчу не заметили проверки: ' + слепые.map(function (р) { return р.имя; }).join('; '));
      process.exit(1);
      return;
    }
    console.log('Ломающий запуск успешен: проверки №2 и №6 корректно покраснели на порченом файле.');
    process.exit(0);
  } finally {
    fs.rmSync(временнаяПапка, { recursive: true, force: true });
  }
}

if (require.main === module) {
  if (process.argv.indexOf('--сломать') !== -1) ломающийПрогон();
  else обычныйПрогон();
}

module.exports = { проверитьВсё, прочитатьВерсииСтраниц, запуститьВПесочнице };
