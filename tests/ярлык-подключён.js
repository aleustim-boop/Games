// Проверка: каждая страница игры, которая считает партии, подключает js/ярлык.js.
// Зачем: очки-рейтинга.js зовёт window.Ярлык?.партияСыграна?.(…) — без файла счёт молча не идёт.
// Запуск: node tests/ярлык-подключён.js [--корень <папка с html>]
const fs = require('fs');
const path = require('path');

const аргументы = process.argv.slice(2);
const номерКорня = аргументы.indexOf('--корень');
const корень = номерКорня >= 0 ? path.resolve(аргументы[номерКорня + 1]) : path.resolve(__dirname, '..');

// Файлы, наличие которых делает страницу кандидатом на ярлык.
const ПРИЗНАКИ = ['js/очки-рейтинга.js', 'js/casual-ui.js', 'js/game.js'];
const ЦЕЛЬ = 'js/ярлык.js';
const МИНИМУМ_СТРАНИЦ = 20;

let проверок = 0;
let провалов = 0;

function проверить(условие, сообщение) {
  проверок++;
  if (!условие) {
    провалов++;
    console.log('ПРОВАЛ: ' + сообщение);
  }
}

// Путь в разметке бывает и кириллицей, и в %-кодировке: приводим к обычному виду.
function нормальныйПуть(src) {
  let путь = src.split('?')[0].split('#')[0];
  try { путь = decodeURIComponent(путь); } catch (_) { /* оставляем как есть */ }
  return путь.replace(/^\.\//, '').replace(/^\//, '');
}

// Возвращает [{путь, версия}] всех script src, комментарии вырезаны заранее.
function подключения(html) {
  const безКомментариев = html.replace(/<!--[\s\S]*?-->/g, '');
  const найдено = [];
  const шаблон = /<script\b[^>]*?\bsrc\s*=\s*["']([^"']+)["']/gi;
  let совпадение;
  while ((совпадение = шаблон.exec(безКомментариев)) !== null) {
    const src = совпадение[1];
    const версия = (src.match(/[?&]v=([^&#]*)/) || [])[1] || '';
    найдено.push({ путь: нормальныйПуть(src), версия });
  }
  return найдено;
}

const страницы = fs.readdirSync(корень).filter((имя) => имя.toLowerCase().endsWith('.html'));
const кандидаты = [];
const версииЯрлыка = new Set();

for (const имя of страницы) {
  const html = fs.readFileSync(path.join(корень, имя), 'utf8');
  const список = подключения(html);
  if (!список.some((п) => ПРИЗНАКИ.includes(п.путь))) continue;
  кандидаты.push(имя);
  const ярлык = список.filter((п) => п.путь === ЦЕЛЬ);
  проверить(ярлык.length > 0, имя + ': не подключён ' + ЦЕЛЬ + ' (или он только в комментарии)');
  ярлык.forEach((п) => версииЯрлыка.add(п.версия));
}

// Ноль найденного — провал: переименуют файлы, и проверка не должна молча позеленеть.
проверить(кандидаты.length >= МИНИМУМ_СТРАНИЦ,
  'найдено страниц-кандидатов ' + кандидаты.length + ', ожидалось не меньше ' + МИНИМУМ_СТРАНИЦ);
проверить(версииЯрлыка.size === 1,
  'номер ?v= у ярлык.js должен быть один на всех страницах, найдено: ' + [...версииЯрлыка].join(', '));

console.log('Страниц-кандидатов: ' + кандидаты.length);
console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
process.exit(провалов > 0 ? 1 : 0);
