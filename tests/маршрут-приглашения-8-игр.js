/** Кусок исходника game.js от начала «откуда» до строки «}» / «};» в начале. */
function вырезать(откуда, конец) {
  const начало = ИСХОДНИК_ИГРЫ.indexOf(откуда);
  if (начало === -1) return '';
  const хвост = ИСХОДНИК_ИГРЫ.indexOf(конец, начало);
  if (хвост === -1) return '';
  return ИСХОДНИК_ИГРЫ.slice(начало, хвост + конец.length);
}

