console.log('\n6. Один набор строк: клиент и сервер (разобратьСсылкуЗаСтол)');
/* Данные сервера — во временную папку: require сервера не должен
   трогать боевые файлы. */
const os = require('os');
process.env.ДАННЫЕ_ИГРЫ = fs.mkdtempSync(path.join(os.tmpdir(), 'маршрут-приглашения-'));
const сервер = require(path.join(КОРЕНЬ, 'server', 'сервер.js'));
const НАЧАЛО_ССЫЛКИ = 'https://t.me/BoardingGames_bot/BoardGames?startapp=';
/* Правило очистки кода у клиента (очиститьКод в js/сеть.js): сервер
   отдаёт код как есть, клиент — заглавными, без лишних знаков, до 6. */
function очиститьКод(что) {
  return String(что || '').toUpperCase().replace(/[^A-Z0-9]/g, '').slice(0, 6);
}
const НАБОР = [
  { строка: 'nardy_K7PQ_Ab12Cd34-' + БУКВЫ, номер: 'Ab12Cd34' },
  { строка: 'nardy_K7PQ-' + БУКВЫ, номер: '' },
  { строка: 'nardy_K7PQ_Ab12Cd34', номер: 'Ab12Cd34' },
  { строка: 'K7PQ_Ab12Cd34-' + БУКВЫ, номер: 'Ab12Cd34' },
  { строка: 'deberts_K7PQ_ab1-' + БУКВЫ, номер: '' },          // номер короче 4
  { строка: 'deberts_K7PQ__Ab12-' + БУКВЫ, номер: '' },        // два «_»
  { строка: 'catan_k7pq_Ab12Cd34-' + БУКВЫ, номер: '' },       // код строчными
  { строка: 'catan_K7_Ab12Cd34-' + БУКВЫ, номер: '' },         // код короче 4
  { строка: 'monopoly_K7PQ-' + БУКВЫ + '.' + СТАРЫЙ_НОМЕР, номер: СТАРЫЙ_НОМЕР }
];
{
  const { окно } = поднятьСеть('', '');
  let сверено = 0;
  for (const случай of НАБОР) {
    const у = окно.Сеть.разобратьПриглашение(случай.строка);
    const с = сервер.разобратьСсылкуЗаСтол(НАЧАЛО_ССЫЛКИ + случай.строка);
    const годно = !!у && !!с &&
      (у.приглашение || '') === (с.приглашение || '') &&
      (у.приглашение || '') === случай.номер &&
      у.код === очиститьКод(с.код) && у.игра === с.игра;
    проверить(годно, '«' + случай.строка.slice(0, 26) + '…» клиент: ' +
      (у ? у.игра + ' / ' + у.код + ' / «' + (у.приглашение || '') + '»' : 'ничего') + '; сервер: ' +
      (с ? с.игра + ' / ' + с.код + ' / «' + (с.приглашение || '') + '»' : 'ничего'));
    сверено++;
  }
  проверить(сверено === НАБОР.length && НАБОР.length >= 9, 'сверено строк: ' + сверено);
}

