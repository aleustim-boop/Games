/* Ответы сервера на /войти — как отдаёт fetch. */
function ответСервера(номер, данные) {
  return Promise.resolve({
    ok: номер >= 200 && номер < 300, status: номер,
    json: function () { return Promise.resolve(данные); }
  });
}
const СЕРВЕР_ПУСТИТ = function (путь) {
  if (путь.indexOf('/войти') === 0) return ответСервера(200, { код: КОД, пропуск: 'пропуск-1' });
  return new Promise(function () {});        // опрос стола и прочее — молчат
};
const СЕРВЕР_ОТКАЖЕТ = function (путь) {
  if (путь.indexOf('/войти') === 0) return ответСервера(403, { ошибка: 'Стол закрыт', почему: 'закрыта' });
  return new Promise(function () {});
};
const СВЯЗЬ_ОБОРВАЛАСЬ = function () { return Promise.reject(new Error('нет связи')); };

/** Дать обещаниям ответа сервера доехать до конца. */
async function дождаться() {
  for (let раз = 0; раз < 20; раз++) await new Promise(function (г) { setImmediate(г); });
}

/** Открыть нарды по ссылке в «вкладке» и вернуть, сколько раз стучались в /войти. */
async function открытьНарды(параметр, вкладка, сервер, имяОкна) {
  const запросы = [];
  const с = поднятьСеть('нарды', параметр, вкладка, { сервер: сервер, запросы: запросы, имяОкна: имяОкна });
  await дождаться();
  return { поле: с.полеКода.value, входов: запросы.filter(function (п) { return п.indexOf('/войти') === 0; }).length };
}

async function проверитьВходПоСсылке() {
  console.log('\n5. Страница игры: тот же start_param — за стол один раз');
  const параметр = 'nardy_' + КОД + '_' + НОМЕР + '-' + БУКВЫ;

  // Сервер пустил — возврат в нарды в той же сессии за старый стол не сажает.
  let вкладка = сделатьПамять();
  let раз1 = await открытьНарды(параметр, вкладка, СЕРВЕР_ПУСТИТ);
  проверить(раз1.поле === КОД && раз1.входов === 1,
    'пустил: первое открытие — вход за стол ' + КОД + ' (в поле «' + раз1.поле + '», /войти: ' + раз1.входов + ')');
  let раз2 = await открытьНарды(параметр, вкладка, СЕРВЕР_ПУСТИТ);
  проверить(раз2.поле === '' && раз2.входов === 0,
    'пустил: вернулись в нарды в той же сессии — за старый стол не садимся (/войти: ' + раз2.входов + ')');

  // Сервер отказал (стол закрыт) — тоже не долбим.
  вкладка = сделатьПамять();
  await открытьНарды(параметр, вкладка, СЕРВЕР_ОТКАЖЕТ);
  раз2 = await открытьНарды(параметр, вкладка, СЕРВЕР_ОТКАЖЕТ);
  проверить(раз2.входов === 0, 'отказал «закрыта»: повторно не стучимся (/войти: ' + раз2.входов + ')');

  // Обрыв связи — перезагрузка в той же сессии пробует снова.
  вкладка = сделатьПамять();
  раз1 = await открытьНарды(параметр, вкладка, СВЯЗЬ_ОБОРВАЛАСЬ);
  раз2 = await открытьНарды(параметр, вкладка, СЕРВЕР_ПУСТИТ);
  проверить(раз1.входов === 1 && раз2.поле === КОД && раз2.входов === 1,
    'обрыв: после перезагрузки в той же сессии снова входим (/войти: ' + раз1.входов + ' и ' + раз2.входов + ')');

  // Новая сессия Telegram с той же ссылкой — снова за стол.
  const новаяСессия = await открытьНарды(параметр, сделатьПамять(), СЕРВЕР_ПУСТИТ);
  проверить(новаяСессия.поле === КОД && новаяСессия.входов === 1,
    'новая сессия с той же ссылкой — снова за стол (/войти: ' + новаяСессия.входов + ')');

  // Без sessionStorage: запас — имя окна, повторного входа тоже нет.
  const имяОкна = { значение: '' };
  const н1 = await открытьНарды(параметр, запрещённаяПамять(), СЕРВЕР_ПУСТИТ, имяОкна);
  const н2 = await открытьНарды(параметр, запрещённаяПамять(), СЕРВЕР_ПУСТИТ, имяОкна);
  проверить(н1.входов === 1 && н2.входов === 0,
    'без sessionStorage: вход один раз, запас — имя окна (/войти: ' + н1.входов + ' и ' + н2.входов + ')');
}

