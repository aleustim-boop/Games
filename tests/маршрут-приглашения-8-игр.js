/** sessionStorage, который запрещён: любое обращение бросает (инкогнито). */
function запрещённаяПамять() {
  const бросить = function () { throw new Error('память вкладки запрещена'); };
  return { getItem: бросить, setItem: бросить, removeItem: бросить };
}

/** Память браузера в виде ящика — одна на «вкладку», если её передать. */
function сделатьПамять() {
  const ящик = new Map();
  return {
    getItem: function (к) { return ящик.has(к) ? ящик.get(к) : null; },
    setItem: function (к, з) { ящик.set(к, String(з)); },
    removeItem: function (к) { ящик.delete(к); }
  };
}

/**
 * Окно с сетью: страница игры «игра», в решётке — startapp «параметр».
 * «вкладка» — общая память вкладки (sessionStorage) между загрузками
 * страниц одной сессии Telegram; не передали — своя, пустая.
 * Поле кода — единственный настоящий узел: по нему видно, села ли
 * страница за стол по ссылке (вход по приглашению вписывает туда код).
 * настройки.сервер(путь) — ответ сервера (обещание fetch); нет — сервер
 * молчит вечно. настройки.имяОкна — { значение } общий на «вкладку»:
 * window.name переживает переходы между страницами одной вкладки.
 * настройки.запросы — сюда пишутся пути запросов.
 */
function поднятьСеть(игра, параметр, вкладка, настройки) {
  const н = настройки || {};
  const имяОкна = н.имяОкна || { значение: '' };
  const память = сделатьПамять();
  const полеКода = { value: '', focus: function () {}, addEventListener: function () {} };
  const окно = {
    get name() { return имяОкна.значение; },
    set name(что) { имяОкна.значение = String(что); },
    location: {
      search: '', protocol: 'https:', host: 'example.github.io',
      origin: 'https://example.github.io', pathname: '/Games/index.html',
      hash: параметр ? '#tgWebAppStartParam=' + encodeURIComponent(параметр) : '',
      href: 'https://example.github.io/Games/index.html' +
            (параметр ? '#tgWebAppStartParam=' + encodeURIComponent(параметр) : ''),
      replace: function (куда) { окно.ушлиНа = куда; }
    },
    localStorage: память, sessionStorage: вкладка || сделатьПамять(),
    addEventListener: function () {},
    btoa: function (с) { return Buffer.from(с, 'binary').toString('base64'); },
    atob: function (с) { return Buffer.from(с, 'base64').toString('binary'); }
  };
  if (игра) окно.ИграСтраницы = игра;
  const страница = {
    getElementById: function (имя) { return имя === 'поле-кода' ? полеКода : null; },
    addEventListener: function () {},
    querySelector: function () { return null; },
    querySelectorAll: function () { return []; },
    readyState: 'complete'
  };
  const окружение = {
    window: окно, document: страница,
    console: { log: function () {}, warn: function () {}, error: function () {} },
    fetch: function (адрес) {
      const путь = decodeURIComponent(String(адрес)).replace(/^https?:\/\/[^/]+/, '');
      if (н.запросы) н.запросы.push(путь);
      // Сервера не назвали — молчит вечно: разбору и переброске он не нужен.
      return н.сервер ? н.сервер(путь) : new Promise(function () {});
    },
    setTimeout: function () { return 0; }, clearTimeout: function () {},
    setInterval: function () { return 0; }, clearInterval: function () {},
    URLSearchParams: URLSearchParams, URL: URL, AbortController: AbortController,
    Promise: Promise, JSON: JSON, Date: Date, Math: Math
  };
  окружение.globalThis = окружение;
  vm.runInNewContext(ИСХОДНИК_СЕТИ, окружение, { filename: 'js/сеть.js' });
  return { окно: окно, окружение: окружение, полеКода: полеКода };
}

