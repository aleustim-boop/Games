function случаи(строка) {
  const начала = [строка.метка + '_'];
  // Дурак обязан понимать и ссылки без метки — такими они были всегда.
  if (строка.игра === 'дурак') начала.push('');
  const список = [];
  for (const начало of начала) {
    const кто = начало ? начало.replace(/_$/, '') : 'без метки';
    список.push({ имя: кто + ' старая', текст: начало + КОД + '-' + БУКВЫ, номер: '', адрес: true });
    список.push({ имя: кто + ' новая с ИД', текст: начало + КОД + '_' + НОМЕР + '-' + БУКВЫ, номер: НОМЕР, адрес: true });
    список.push({ имя: кто + ' с ИД без адреса', текст: начало + КОД + '_' + НОМЕР, номер: НОМЕР, адрес: false });
    список.push({ имя: кто + ' прежний хвост .id', текст: начало + КОД + '-' + БУКВЫ + '.' + СТАРЫЙ_НОМЕР, номер: СТАРЫЙ_НОМЕР, адрес: true });
  }
  return список;
}

