проверкаВсехПорядков();

первыеПровалы.forEach(function (т) { console.log('  ПРОВАЛ: ' + т); });
if (провалов > первыеПровалы.length) console.log('  … и ещё ' + (провалов - первыеПровалы.length));
console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
// Ноль проверок — тоже провал: значит, ничего не нашли и не проверили.
process.exit(провалов === 0 && проверок > 1000 ? 0 : 1);
