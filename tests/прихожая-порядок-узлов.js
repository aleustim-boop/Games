/* =====================================================================
   ПРИХОЖАЯ: ПОРЯДОК ПЕРЕЕЗЖАЮЩИХ УЗЛОВ.

   Зачем. общее/js/дурак-комната.js при показе комнаты переносит шесть узлов
   (код, «Пригласить», обе строки сообщений, «Скопировать код», «Выйти»)
   из запасной прихожей #комната-старая в новый вид, а при спрятать()
   возвращает обратно. Раньше возврат шёл через «соседа справа»: если
   сосед сам был переезжающим (шаблон общее/js/онлайн-лобби.js ставит код и
   «Скопировать» вплотную), insertBefore падал с «not a child of this
   node», и у гостя деберца не появлялся стол.

   Как проверяем. Песочница node:vm с маленьким поддельным DOM (jsdom
   в проекте нет). Из НАСТОЯЩЕГО общее/js/дурак-комната.js вырезается раздел
   «Переезд шести узлов» и гоняется:
     1) на настоящем шаблоне общее/js/онлайн-лобби.js (подключить() на пустой
        странице — как у деберца);
     2) на всех 720 порядках шести узлов подряд без пробелов;
     3) на порядках с узлами, сгруппированными по вложенным div.
   Каждый раз: туда — обратно — туда — обратно, без исключения; после
   возврата порядок узлов и их родители — как в исходной разметке; в
   новом виде каждый узел стоит прямо перед своей меткой «место-…».

   Запуск:
     node tests/прихожая-порядок-узлов.js
     node tests/прихожая-порядок-узлов.js --файл <путь к копии дурак-комната.js>
     node tests/прихожая-порядок-узлов.js --сломать
       — копирует общее/js/дурак-комната.js во временную папку, возвращает в
         копии старый возврат через соседа справа и гоняет проверку на
         копии. Обязана покраснеть (код выхода 0 — только если покраснела).
   ===================================================================== */

