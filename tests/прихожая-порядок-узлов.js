/* ---------- Поддельный DOM ---------- */

class Узел {
  constructor(тип, имя) {
    this.nodeType = тип;          // 1 — элемент, 3 — текст, 8 — комментарий
    this.tagName = имя || '';
    this.childNodes = [];
    this.parentNode = null;
    this.id = '';
    this.className = '';
    this.атрибуты = {};
    this._текст = '';
    const сам = this;
    this.classList = {
      contains(к) { return сам.className.split(/\s+/).includes(к); }
    };
  }
  get children() { return this.childNodes.filter(function (д) { return д.nodeType === 1; }); }
  get firstChild() { return this.childNodes[0] || null; }
  get nextSibling() {
    if (!this.parentNode) return null;
    const д = this.parentNode.childNodes;
    return д[д.indexOf(this) + 1] || null;
  }
  set textContent(т) { this._текст = String(т); }
  get textContent() { return this._текст; }
  set innerHTML(т) { this._текст = String(т); }
  setAttribute(имя, знач) { this.атрибуты[имя] = String(знач); }
  removeChild(ребёнок) {
    const i = this.childNodes.indexOf(ребёнок);
    if (i < 0) throw new Error('removeChild: узел не ребёнок этого узла');
    this.childNodes.splice(i, 1);
    ребёнок.parentNode = null;
    return ребёнок;
  }
  insertBefore(новый, передКем) {
    // Как настоящий DOM: сосед обязан быть ребёнком именно этого узла.
    if (передКем && передКем.parentNode !== this) {
      throw new Error("Failed to execute 'insertBefore' on 'Node': The node before which the new node is to be inserted is not a child of this node.");
    }
    if (новый.parentNode) новый.parentNode.removeChild(новый);
    const i = передКем ? this.childNodes.indexOf(передКем) : this.childNodes.length;
    this.childNodes.splice(i, 0, новый);
    новый.parentNode = this;
    return новый;
  }
  appendChild(новый) { return this.insertBefore(новый, null); }
}

function новыйДокумент() {
  const body = new Узел(1, 'BODY');
  function обойти(корень, id) {
    if (корень.nodeType === 1 && корень.id === id) return корень;
    for (const д of корень.childNodes) {
      const н = обойти(д, id);
      if (н) return н;
    }
    return null;
  }
  return {
    body: body,
    createElement(имя) { return new Узел(1, String(имя).toUpperCase()); },
    createComment(т) { const у = new Узел(8); у._текст = т; return у; },
    createTextNode(т) { const у = new Узел(3); у._текст = т; return у; },
    getElementById(id) { return обойти(body, id); },
    addEventListener() {}
  };
}

function элемент(док, имя, id, ...дети) {
  const у = док.createElement(имя);
  if (id) у.id = id;
  дети.forEach(function (д) { у.appendChild(д); });
  return у;
}

/* ---------- Раздел переезда из настоящего файла ---------- */

function разделПереезда(путь) {
  const текст = fs.readFileSync(путь, 'utf8');
  const начало = текст.indexOf('/* ---------- Переезд шести узлов');
  const конец = текст.indexOf('/* ---------- Всё вместе');
  if (начало < 0 || конец < 0 || конец <= начало) {
    throw new Error('В ' + путь + ' не найден раздел «Переезд шести узлов» — проверка не может работать');
  }
  return текст.slice(начало, конец);
}

const РАЗДЕЛ = разделПереезда(путьКомнаты);

/** Двери переезда, привязанные к данному документу. */
function переезд(док) {
  const песочница = { document: док };
  vm.createContext(песочница);
  vm.runInContext(
    'function узел(id) { return document.getElementById(id); }\n' + РАЗДЕЛ +
    '\n;this.туда = перенестиУзлыВНовыйВид; this.обратно = вернутьУзлыВЗапаснуюПрихожую; this.список = ПЕРЕЕЗЖАЮЩИЕ_УЗЛЫ;',
    песочница, { filename: путьКомнаты });
  return песочница;
}

/* ---------- Учёт ---------- */

let проверок = 0;
let провалов = 0;
const первыеПровалы = [];

function провал(что) {
  провалов++;
  if (первыеПровалы.length < 10) первыеПровалы.push(что);
}

function ожидать(условие, что) {
  проверок++;
  if (!условие) провал(что);
}

/* ---------- Снимок положения узлов ---------- */

/** Где стоит каждый переезжающий узел: родитель и порядок среди элементов. */
function снимок(док) {
  return ПЕРЕЕЗЖАЮЩИЕ.map(function (id) {
    const у = док.getElementById(id);
    if (!у || !у.parentNode) return id + ' — нет в документе';
    const род = у.parentNode;
    const элементы = род.children.map(function (д) { return д.id || д.tagName; });
    return id + ' в ' + (род.id || род.tagName) + ' [' + элементы.join(',') + ']';
  }).join(' | ');
}

/** Прогнать туда-обратно дважды; вернуть описание беды или ''. */
function прогнать(док, имя) {
  let двери;
  try {
    двери = переезд(док);
  } catch (ошибка) {
    ожидать(false, имя + ': раздел переезда не запустился — ' + ошибка.message);
    return;
  }
  ожидать(Array.isArray(двери.список) && двери.список.join() === ПЕРЕЕЗЖАЮЩИЕ.join(),
    имя + ': список ПЕРЕЕЗЖАЮЩИЕ_УЗЛЫ в файле не совпал с ожидаемым');
  const исходно = снимок(док);
  for (let круг = 1; круг <= 2; круг++) {
    try {
      двери.туда();
      проверок++;
    } catch (ошибка) {
      провал(имя + ', круг ' + круг + ', туда: ' + ошибка.message);
      return;
    }
    ПЕРЕЕЗЖАЮЩИЕ.forEach(function (id) {
      const у = док.getElementById(id);
      const метка = док.getElementById('место-' + id);
      ожидать(у && метка && у.nextSibling === метка,
        имя + ', круг ' + круг + ': #' + id + ' не стоит перед своей меткой в новом виде');
    });
    try {
      двери.обратно();
      проверок++;
    } catch (ошибка) {
      провал(имя + ', круг ' + круг + ', обратно: ' + ошибка.message);
      return;
    }
    const после = снимок(док);
    ожидать(после === исходно,
      имя + ', круг ' + круг + ': после возврата узлы стоят не так, как в разметке\n    было:  ' + исходно + '\n    стало: ' + после);
  }
}

/* ---------- Новый вид с метками (как в новыйВид() онлайн-лобби) ---------- */

function поставитьНовыйВид(док, экран) {
  const метка = function (id) { return элемент(док, 'span', 'место-' + id); };
  const вид = элемент(док, 'div', 'комната',
    элемент(док, 'div', 'комната-стол'),
    метка('кнопка-позвать-друга'),
    метка('сообщение-приглашения'),
    элемент(док, 'div', 'комната-код-обёртка',
      метка('код-комнаты'),
      метка('кнопка-копировать-код')),
    метка('сообщение-копирования'),
    элемент(док, 'button', 'комната-начать'),
    метка('кнопка-комната-отмена'));
  экран.appendChild(вид);
}

/* ---------- 1. Настоящий шаблон общее/js/онлайн-лобби.js ---------- */

function проверкаНастоящегоШаблона() {
  const док = новыйДокумент();
  const экран = элемент(док, 'section', 'экран-комнаты');
  экран.className = 'экран';
  док.body.appendChild(экран);
  const окно = { document: док, console: console };
  окно.window = окно;
  vm.createContext(окно);
  const путьЛобби = path.join(КОРЕНЬ, 'общее', 'js', 'онлайн-лобби.js');
  vm.runInContext(fs.readFileSync(путьЛобби, 'utf8'), окно, { filename: путьЛобби });
  окно.ОнлайнЛобби.подключить({ игра: 'деберц', мест: { мин: 2, макс: 4, обычно: 4 } });
  // Без этого проверка молча прошла бы мимо главного случая.
  ожидать(Boolean(док.getElementById('комната-старая')), 'онлайн-лобби: шаблон не поставил #комната-старая');
  ПЕРЕЕЗЖАЮЩИЕ.forEach(function (id) {
    ожидать(Boolean(док.getElementById(id)), 'онлайн-лобби: в шаблоне нет #' + id);
    ожидать(Boolean(док.getElementById('место-' + id)), 'онлайн-лобби: в новом виде нет метки место-' + id);
  });
  прогнать(док, 'настоящий шаблон онлайн-лобби');
}

/* ---------- 2. Все порядки подряд, без пробелов ---------- */

function перестановки(список) {
  if (список.length <= 1) return [список.slice()];
  const итог = [];
  список.forEach(function (x, i) {
    const остаток = список.slice(0, i).concat(список.slice(i + 1));
    перестановки(остаток).forEach(function (п) { итог.push([x].concat(п)); });
  });
  return итог;
}

function документСПорядком(порядок, группировка) {
  const док = новыйДокумент();
  const экран = элемент(док, 'section', 'экран-комнаты');
  док.body.appendChild(экран);
  const старая = элемент(док, 'div', 'комната-старая');
  экран.appendChild(старая);
  // группировка — сколько узлов подряд класть в одну вложенную обёртку.
  let i = 0;
  let номерГруппы = 0;
  while (i < порядок.length) {
    const размер = группировка ? группировка[номерГруппы % группировка.length] : 1;
    const часть = порядок.slice(i, i + размер);
    const куда = размер > 1 ? элемент(док, 'div', 'обёртка-' + номерГруппы) : старая;
    if (куда !== старая) старая.appendChild(куда);
    часть.forEach(function (id) { куда.appendChild(элемент(док, 'button', id)); });
    i += размер;
    номерГруппы++;
  }
  поставитьНовыйВид(док, экран);
  return док;
}

function проверкаВсехПорядков() {
  const все = перестановки(ПЕРЕЕЗЖАЮЩИЕ);
  ожидать(все.length === 720, 'перестановок не 720, а ' + все.length);
  все.forEach(function (порядок, н) {
    прогнать(документСПорядком(порядок, null), 'подряд, порядок №' + н + ' [' + порядок.join(',') + ']');
  });
  // Вложенные обёртки разного размера — как .комната__код в шаблоне.
  const группировки = [[2], [3], [2, 1], [1, 2], [2, 2, 2], [6]];
  группировки.forEach(function (г) {
    все.forEach(function (порядок, н) {
      if (н % 7 !== 0) return;   // выборка: каждый седьмой порядок на каждую группировку
      прогнать(документСПорядком(порядок, г), 'обёртки ' + г.join('+') + ', порядок №' + н + ' [' + порядок.join(',') + ']');
    });
  });
}

/* ---------- Ломающий запуск ---------- */

function ломающийЗапуск() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'прихожая-порядок-'));
  const копия = path.join(папка, 'дурак-комната.js');
  const текст = fs.readFileSync(path.join(КОРЕНЬ, 'общее', 'js', 'дурак-комната.js'), 'utf8');
  const начало = текст.indexOf('/* ---------- Переезд шести узлов');
  const конец = текст.indexOf('/* ---------- Всё вместе');
  if (начало < 0 || конец < 0) {
    console.log('Ломающий запуск: раздел «Переезд шести узлов» не найден — ломать нечего, это провал.');
    return 1;
  }
  // Старый возврат: запомнить родителя и соседа справа, вернуть insertBefore'ом.
  const старый = [
    '/* ---------- Переезд шести узлов (СЛОМАНО: старый возврат) ---------- */',
    'const ПЕРЕЕЗЖАЮЩИЕ_УЗЛЫ = [',
    "  'код-комнаты', 'кнопка-позвать-друга', 'сообщение-приглашения',",
    "  'кнопка-копировать-код', 'сообщение-копирования', 'кнопка-комната-отмена'",
    '];',
    'const исходноеМестоУзла = new Map();',
    'function запомнитьИсходноеМесто(id) {',
    '  if (исходноеМестоУзла.has(id)) return;',
    '  const у = узел(id);',
    '  if (у && у.parentNode) исходноеМестоУзла.set(id, { родитель: у.parentNode, передКем: у.nextSibling });',
    '}',
    'function перенестиУзлыВНовыйВид() {',
    '  ПЕРЕЕЗЖАЮЩИЕ_УЗЛЫ.forEach(function (id) {',
    '    запомнитьИсходноеМесто(id);',
    '    const у = узел(id);',
    "    const место = узел('место-' + id);",
    '    if (у && место && место.parentNode) место.parentNode.insertBefore(у, место);',
    '  });',
    '}',
    'function вернутьУзлыВЗапаснуюПрихожую() {',
    '  ПЕРЕЕЗЖАЮЩИЕ_УЗЛЫ.forEach(function (id) {',
    '    const место = исходноеМестоУзла.get(id);',
    '    const у = узел(id);',
    '    if (у && место && место.родитель) место.родитель.insertBefore(у, место.передКем);',
    '  });',
    '}',
    ''
  ].join('\n');
  fs.writeFileSync(копия, текст.slice(0, начало) + старый + текст.slice(конец));
  console.log('Ломающий запуск: копия со старым возвратом — ' + копия);
  const итог = spawnSync(process.execPath, [__filename, '--файл', копия], { encoding: 'utf8' });
  process.stdout.write(итог.stdout || '');
  process.stdout.write(итог.stderr || '');
  if (итог.status === 0) {
    console.log('ЛОМАЮЩИЙ ЗАПУСК НЕ ПОКРАСНЕЛ — проверка ничего не ловит.');
    return 1;
  }
  console.log('Ломающий запуск покраснел, как и должен.');
  return 0;
}

