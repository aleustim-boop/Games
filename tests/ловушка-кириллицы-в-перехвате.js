'use strict';

/* =====================================================================
   ЛОВУШКА КИРИЛЛИЦЫ В ПЕРЕХВАТЕ ЗАПРОСОВ.

   О чём речь. Стенды иногда подменяют ответ сервера: «пусть запрос
   за приглашением вернёт вот это». В playwright это делается так:
   страница.route(шаблон, что делать). Беда в том, что браузер шлёт
   русский адрес закодированным — «/js/похвастаться.js» уходит как
   «/js/%D0%BF%D0%BE%D1%85%D0%B2%D0%B0%D1%81%D1%82%D0%B0%D1%82%D1%8C%D1%81%D1%8F.js»,
   а playwright сверяет шаблон именно с закодированным видом.
   Русский шаблон не совпадает НИКОГДА: запрос тихо уходит на настоящий
   адрес, подмена не срабатывает, а стенд при этом зеленеет — он же
   не знает, что его подмену обошли. Это худший вид поломки проверки:
   молчаливый.

   Этот файл делает три вещи:
     1) показывает ловушку вживую — русский шаблон не ловит запрос;
     2) показывает рабочий способ — перехватываем всё и сверяем сами
        по РАСКОДИРОВАННОМУ адресу (готовая ручка «перехватить»
        лежит в tests/браузер-робот.js);
     3) обходит все стенды в tests/ и краснеет, если в каком-то из них
        снова появился route() с русским шаблоном.

   Запуск (страничный сервер должен быть уже поднят):
       node tests/ловушка-кириллицы-в-перехвате.js
       node tests/ловушка-кириллицы-в-перехвате.js 8080
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const { chromium, перехватить } = require('./браузер-робот.js');

const ПОРТ = Number(process.argv[2]) || 8080;
const АДРЕС = 'http://127.0.0.1:' + ПОРТ + '/';
const РУССКИЙ_ФАЙЛ = '/js/похвастаться.js';   // настоящий файл проекта, адрес с кириллицей

let провалов = 0;
function проверить(условие, слова) {
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}

(async () => {
  const браузер = await chromium.launch();
  console.log('Ловушка кириллицы в перехвате запросов. Страница: ' + АДРЕС);

  /* ---- 1. Русский шаблон: ловит или нет ---- */
  console.log('\n=== 1. Русский шаблон route(«**/js/похвастаться.js*») ===');
  let поймалРусскийШаблон = false;
  {
    const окно = await браузер.newContext();
    const страница = await окно.newPage();
    await страница.route('**' + РУССКИЙ_ФАЙЛ + '*', function (путь) {
      поймалРусскийШаблон = true;
      путь.fulfill({ status: 200, contentType: 'text/plain; charset=utf-8', body: 'ПОДМЕНА' });
    });
    await страница.goto(АДРЕС);
    const что = await страница.evaluate(async (файл) => {
      const о = await fetch(файл);
      return (await о.text()).slice(0, 7);
    }, РУССКИЙ_ФАЙЛ);
    console.log('  страница получила: «' + что + '…»');
    console.log(поймалРусскийШаблон
      ? '  (эта версия playwright сверяет шаблон по раскодированному адресу — ловушки нет)'
      : '  ЛОВУШКА ЖИВА: шаблон с кириллицей не совпал, запрос ушёл на настоящий файл');
    await окно.close();
  }

  /* ---- 2. Рабочий способ: сверка по раскодированному адресу ---- */
  console.log('\n=== 2. Перехват со сверкой по раскодированному адресу ===');
  {
    const окно = await браузер.newContext();
    const страница = await окно.newPage();
    let поймали = false;
    await перехватить(страница, РУССКИЙ_ФАЙЛ, function (путь) {
      поймали = true;
      путь.fulfill({ status: 200, contentType: 'text/plain; charset=utf-8', body: 'ПОДМЕНА' });
    });
    await страница.goto(АДРЕС);
    const что = await страница.evaluate(async (файл) => {
      const о = await fetch(файл);
      return (await о.text()).slice(0, 7);
    }, РУССКИЙ_ФАЙЛ);
    проверить(поймали, 'запрос по русскому адресу перехвачен');
    проверить(что === 'ПОДМЕНА', 'страница получила именно нашу подмену: «' + что + '»');
    await окно.close();
  }

  /* ---- 3. Не завелась ли ловушка в стендах ---- */
  console.log('\n=== 3. Обход всех стендов: нет ли route() с кириллицей ===');
  {
    const русская = /[А-Яа-яЁё]/;
    const сомнительные = [];
    let сroute = 0;
    for (const имя of fs.readdirSync(__dirname)) {
      if (!имя.endsWith('.js')) continue;
      const текст = fs.readFileSync(path.join(__dirname, имя), 'utf8');
      const строки = текст.split('\n');
      строки.forEach((строка, номер) => {
        const начало = строка.trim();
        // строки-пояснения не считаем: там route() упомянут словами, а не вызван
        if (начало.startsWith('*') || начало.startsWith('//') || начало.startsWith('/*')) return;
        const м = /\.route\(\s*(['"`])([^'"`]*)\1/.exec(строка);
        if (!м) return;
        сroute++;
        if (русская.test(м[2])) сомнительные.push(имя + ':' + (номер + 1) + ' — шаблон «' + м[2] + '»');
      });
    }
    console.log('  перехватов route() в стендах: ' + сroute);
    if (сомнительные.length) сомнительные.forEach((с) => console.log('    ' + с));
    проверить(сомнительные.length === 0,
      'ни в одном стенде нет route() с русским шаблоном' +
      (сомнительные.length ? ' (нашлось ' + сомнительные.length + ', чинить сверкой по раскодированному адресу — см. «перехватить» в tests/браузер-робот.js)' : ''));
  }

  await браузер.close();
  console.log('\nИтог: провалов ' + провалов);
  process.exit(провалов ? 1 : 0);
})().catch((о) => { console.error('Стенд упал: ' + (о && о.stack || о)); process.exit(2); });
