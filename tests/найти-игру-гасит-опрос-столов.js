async function видимыйЭкран(страница) {
  return страница.evaluate(() => {
    const э = document.querySelector('.экран.экран--виден');
    return э ? э.id : '';
  });
}
async function дождаться(страница, экран, мс) {
  await страница.waitForFunction((и) => {
    const э = document.querySelector('.экран.экран--виден');
    return Boolean(э && э.id === и);
  }, экран, { timeout: мс || 8000 });
}
async function нажать(страница, локатор) {
  await локатор.first().click({ timeout: 5000 });
}

/** От витрины до экрана «Играть онлайн» — та же дорога, что в
    tests/найти-игру-в-браузере.js: лобби дурака → карточка
    «лобби-играть-онлайн». */
async function дойтиДоНайтиИгру(страница) {
  await страница.waitForSelector('#кнопка-игра-дурак', { state: 'visible', timeout: 8000 });
  await нажать(страница, страница.locator('#кнопка-игра-дурак'));
  await дождаться(страница, 'экран-лобби');
  await нажать(страница, страница.locator('#лобби-играть-онлайн'));
  await дождаться(страница, ЭКРАН_СТОЛОВ);
}

function следитьЗаКонсолью(страница, красные) {
  страница.on('pageerror', (о) => красные.push('падение страницы: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const текст = м.text();
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js|telegram\.org/.test(текст + ' ' + откуда)) return;
    красные.push('консоль: ' + текст + (откуда ? ' (' + откуда + ')' : ''));
  });
}

/* Игрок без фото в Telegram честно получает 404 на дверь /фото/<ключ>
   (та же находка, что описана в tests/найти-игру-в-браузере.js) — не даём
   ей маскировать под собой настоящие поломки этой проверки. */
const ПОДДЕЛЬНОЕ_ФОТО = Buffer.from(
  'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=',
  'base64');
async function игнорироватьЗапросыФото(страница) {
  await страница.route('**/*', (route) => {
    let адрес = route.request().url();
    try { адрес = decodeURIComponent(адрес); } catch (сбой) { /* оставим как есть */ }
    if (/\/фото\/[0-9a-f]{24}(?:\?|$)/.test(адрес)) {
      route.fulfill({ status: 200, contentType: 'image/png', body: ПОДДЕЛЬНОЕ_ФОТО });
    } else {
      route.fallback();
    }
  });
}

