/* =====================================================================
   ОБЩИЙ ГЕНЕРАТОР СЛУЧАЙНЫХ ЧИСЕЛ ДЛЯ ЗАМЕРОВ.

   ЗАЧЕМ ОН НУЖЕН. Замерам нужна случайность, которую можно повторить:
   нашли поломку в партии №417 — хотим открыть ровно её же ещё раз.
   Обычный Math.random так не умеет, поэтому во всех наших замерах стоит
   свой генератор, которому можно назвать «зерно» — число, с которого
   он начинает. Одно зерно — одна и та же раздача, сколько ни запускай.

   ГДЕ ЖИВЁТ ФОРМУЛА. Не здесь. Повторимый поток теперь есть в самих
   правилах — «создатьПоток» в js/game.js: он нужен «раздаче дня» (все,
   кто сел играть сегодня, получают одни и те же карты). Раньше формула
   лежала здесь копией, и правило «менять в двух местах разом» держалось
   на дисциплине. Теперь этот файл — только удобная обёртка над дверью
   правил: одно зерно даёт одну раздачу и в игре, и в замерах, потому что
   считает их один и тот же код. Сверено: тысяча чисел подряд совпадает.

   ЧТО БЫЛО ДО ЭТОГО (и почему старые отчёты не воспроизводятся). Первый
   генератор считал «зерно * 1103515245» в обычных числах JavaScript,
   терял младшие разряды и ходил по кругу из 11–16 тысяч чисел; раздачи
   выходили слишком ровными, а «погрешность» в скобках врала. Его заменили
   честной 32-разрядной арифметикой (Math.imul и «|0») — и номера партий
   из отчётов, сделанных до той замены, больше не воспроизводятся.

   Как пользоваться:

       const генератор = require('./общий-генератор.js');
       генератор.захватитьСлучайность();   // подменяем Math.random
       генератор.поставитьЗерно(12345);    // и дальше раздача повторима

   Самопроверка (печатает, насколько ровно ложатся числа):

       node tests/общий-генератор.js
   ===================================================================== */

const игра = require(require('path').join(__dirname, '..', 'js', 'game.js'));

/* Поставленное зерно и поток правил, начатый с него. */
let зерно = 1;
let поток = игра.создатьПоток(зерно);

/** Следующее случайное число от 0 (включительно) до 1 (не включительно). */
function следующее() {
  return поток();
}

/**
 * Начать с названного числа. Одно и то же зерно — одна и та же
 * последовательность, а значит и одна и та же раздача.
 * Приводим зерно так же, как правила: целое 32-разрядное, иначе 1.
 */
function поставитьЗерно(число) {
  const целое = Number(число);
  зерно = Number.isFinite(целое) ? (Math.floor(целое) | 0) : 1;
  поток = игра.создатьПоток(зерно);
}

/** Какое зерно поставлено — чтобы замер записал его в отчёт.
    Внутреннее состояние потока правила наружу не отдают, и оно тут не нужно:
    воспроизводят раздачу по зерну, а не по состоянию посередине. */
function текущееЗерно() {
  return зерно;
}

/**
 * Подменить Math.random этим генератором. После вызова вся игра
 * (тасовка колоды, ошибки лёгкого бота) тасуется повторимо.
 */
function захватитьСлучайность() {
  Math.random = следующее;
}

/**
 * Отдельный, ни с кем не связанный поток случайных чисел со своим зерном.
 *
 * Нужен там, где проверка НЕ подменяет Math.random, а держит генератор
 * при себе, — например, чтобы выбирать ходы, но оставить тасовку колоды
 * в покое. Два таких потока не мешают друг другу: у каждого своё состояние.
 * Это та же дверь правил, что и у всего файла.
 */
function создатьПоток(своёЗерно) {
  return игра.создатьПоток(своёЗерно);
}

module.exports = {
  следующее: следующее,
  поставитьЗерно: поставитьЗерно,
  текущееЗерно: текущееЗерно,
  захватитьСлучайность: захватитьСлучайность,
  создатьПоток: создатьПоток
};

/* =====================================================================
   САМОПРОВЕРКА. Запускается только когда файл открыт напрямую:
   node tests/общий-генератор.js
   Печатает три меры ровности чисел; сравнивать есть с чем — старый,
   сломанный генератор давал круг из 11–16 тысяч и 18–21 разных младших
   байтов из 256.
   ===================================================================== */
if (require.main === module) {
  поставитьЗерно(12345);
  const ВСЕГО = 200000;
  const младшие = new Set();
  const масти = [0, 0, 0, 0];
  const первые = [];
  let круг = 0;
  for (let i = 0; i < ВСЕГО; i++) {
    const ч = следующее();
    младшие.add(Math.floor(ч * 4294967296) & 255);
    масти[Math.floor(ч * 4)]++;
    if (i < 64) первые.push(ч);
    else if (!круг && ч === первые[0]) {
      // Вернулись к первому числу — проверяем, не пошёл ли круг.
      let совпало = true;
      for (let k = 1; k < 8; k++) { if (следующее() !== первые[k]) { совпало = false; break; } }
      if (совпало) круг = i;
    }
  }
  console.log('=== Самопроверка общего генератора (поток правил js/game.js) ===');
  console.log('чисел: ' + ВСЕГО + ', разных младших байтов: ' + младшие.size + ' из 256');
  console.log('«масть» по четвертям: ' + масти.join(' / ') + ' (ровно поровну быть не должно, но и перекоса тоже)');
  console.log('круг найден: ' + (круг ? 'через ' + круг + ' чисел — ПЛОХО' : 'нет за ' + ВСЕГО + ' чисел'));
  const плохо = младшие.size < 250 || круг > 0;
  console.log(плохо ? '=== Итог: генератор негодный ===' : '=== Итог: генератор годный ===');
  process.exit(плохо ? 1 : 0);
}
