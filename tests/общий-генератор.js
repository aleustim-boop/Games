'use strict';

/* =====================================================================
   ОБЩИЙ ГЕНЕРАТОР СЛУЧАЙНЫХ ЧИСЕЛ ДЛЯ ЗАМЕРОВ.

   ЗАЧЕМ ОН НУЖЕН. Замерам нужна случайность, которую можно повторить:
   нашли поломку в партии №417 — хотим открыть ровно её же ещё раз.
   Обычный Math.random так не умеет, поэтому во всех наших замерах стоит
   свой генератор, которому можно назвать «зерно» — число, с которого он
   начинает. Одно зерно — одна и та же раздача, сколько ни запускай.

   ПОЧЕМУ ПОТРЕБОВАЛСЯ НОВЫЙ. Раньше в каждом замере лежала своя копия
   такого генератора, и все копии были одинаково сломаны:

       зерно = (зерно * 1103515245 + 12345) % 2147483648

   Умножение здесь доходит до 2 300 000 000 000 000 000, а JavaScript
   считает целые числа точно только примерно до 9 000 000 000 000 000 —
   в 250 раз меньше. Всё, что не влезло, округляется, и младшие разряды
   пропадают. Замерено (см. самопроверку внизу файла):

     • генератор ходит по кругу всего из 11-16 тысяч чисел вместо
       двух миллиардов — то есть очень быстро начинает повторяться;
     • младший байт принимает не 256 разных значений, а 18-21;
     • «выбери одно число из 36» на длинной ленте перекошено так, что
       редкий вариант выпадает на треть реже частого.

   Отдельно вылезло самое неприятное для замеров: раздачи получались
   НЕ СЛУЧАЙНЫМИ, а слишком ровными. На четырёх тысячах раздач масть
   козыря выпадала 1002 / 1001 / 999 / 998 раз — так ровно случайность
   не ложится НИКОГДА. А это значит, что «погрешность», которую замер
   печатает в скобках, посчитана по формуле для случайной выборки,
   а выборка случайной не была: верить скобкам было нельзя.

   ЧТО ЗДЕСЬ ВМЕСТО НЕГО. Тот же приём (число из зерна), но все действия —
   через Math.imul и «|0», то есть в честной 32-разрядной целой арифметике,
   где ничего не округляется. Повторяемость сохранилась полностью: то же
   зерно — та же раздача.

   ВАЖНО ПРО СТАРЫЕ ОТЧЁТЫ: номера партий из отчётов, сделанных ДО этой
   правки, больше не воспроизводятся — раздачи под теми же зёрнами теперь
   другие. Поэтому генератор и заменён сразу во всех замерах одним шагом,
   а не по одному файлу.

   Как пользоваться:

       const генератор = require('./общий-генератор.js');
       генератор.захватитьСлучайность();   // подменяем Math.random
       генератор.поставитьЗерно(12345);    // и дальше раздача повторима

   Самопроверка (печатает, насколько ровно ложатся числа):

       node tests/общий-генератор.js
   ===================================================================== */

/* Текущее состояние генератора. Всегда целое 32-разрядное число. */
let состояние = 1;

/**
 * Следующее случайное число от 0 (включительно) до 1 (не включительно).
 *
 * Внутри — перемешивание разрядов числа-счётчика. Читать эти строчки
 * как формулу не нужно, важно одно: здесь нет ни одного умножения,
 * которое вылезло бы за точный счёт, — Math.imul нарочно умножает
 * «как целое 32-разрядное», отбрасывая лишнее сразу и предсказуемо.
 */
function следующее() {
  состояние = (состояние + 0x6D2B79F5) | 0;
  let т = Math.imul(состояние ^ (состояние >>> 15), 1 | состояние);
  т = (т + Math.imul(т ^ (т >>> 7), 61 | т)) ^ т;
  return ((т ^ (т >>> 14)) >>> 0) / 4294967296;
}

/**
 * Начать с названного числа. Одно и то же зерно — одна и та же
 * последовательность, а значит и одна и та же раздача.
 */
function поставитьЗерно(число) {
  const целое = Number(число);
  состояние = Number.isFinite(целое) ? (Math.floor(целое) | 0) : 1;
}

/** Какое сейчас состояние — иногда нужно замеру, чтобы записать его в отчёт. */
function текущееЗерно() {
  return состояние;
}

/**
 * Подменить Math.random этим генератором. После вызова вся игра
 * (тасовка колоды, ошибки лёгкого бота) тасуется повторимо.
 */
function захватитьСлучайность() {
  Math.random = следующее;
}

/**
 * Отдельный, ни с кем не связанный поток случайных чисел со своим зерном.
 *
 * Нужен там, где проверка НЕ подменяет Math.random, а держит генератор
 * при себе, — например, чтобы выбирать ходы, но оставить тасовку колоды
 * в покое. Два таких потока не мешают друг другу: у каждого своё состояние,
 * и вызовы одного не сдвигают другой.
 *
 * Вернёт функцию: зовёшь без доводов, получаешь число от 0 до 1.
 */
function создатьПоток(зерно) {
  const целое = Number(зерно);
  let своё = Number.isFinite(целое) ? (Math.floor(целое) | 0) : 1;
  return function () {
    своё = (своё + 0x6D2B79F5) | 0;
    let т = Math.imul(своё ^ (своё >>> 15), 1 | своё);
    т = (т + Math.imul(т ^ (т >>> 7), 61 | т)) ^ т;
    return ((т ^ (т >>> 14)) >>> 0) / 4294967296;
  };
}

module.exports = {
  следующее: следующее,
  поставитьЗерно: поставитьЗерно,
  текущееЗерно: текущееЗерно,
  захватитьСлучайность: захватитьСлучайность,
  создатьПоток: создатьПоток
};

/* =====================================================================
   САМОПРОВЕРКА. Запускается только когда файл открыт напрямую:
   node tests/общий-генератор.js
   Печатает три меры и рядом — что показывал старый, сломанный генератор,
   чтобы разницу было видно без веры на слово.
   ===================================================================== */

if (require.main === module) {
  /* Старый, сломанный генератор — держим здесь ТОЛЬКО ради сравнения
     в этой самопроверке. В самих замерах он больше нигде не используется. */
  function старыйСломанный(начало) {
    let з = начало;
    return function () {
      з = (з * 1103515245 + 12345) % 2147483648;
      return з;
    };
  }
  /* У нового генератора внутреннее состояние и выданное число — РАЗНЫЕ вещи
     (состояние просто считает по порядку, а наружу отдаётся перемешанное).
     Поэтому берём отдельно то и другое: мера про повторяемость смотрит
     на состояние, а меры про ровность — на то, что генератор реально выдал.
     У старого генератора состояние и выданное число — одно и то же. */
  function состояниеНового(начало) {
    поставитьЗерно(начало);
    return function () { следующее(); return состояние >>> 0; };
  }
  function выходНового(начало) {
    поставитьЗерно(начало);
    return следующее;
  }
  /* «Что генератор выдал» приводим к одному виду — доле от 0 до 1, —
     иначе сравнение получится нечестным: старый отдаёт числа до двух
     миллиардов, новый — до четырёх, и без приведения старый выглядел бы
     перекошенным просто из-за другого масштаба. */
  function выходСтарого(начало) {
    const шаг = старыйСломанный(начало);
    return function () { return шаг() / 2147483648; };
  }

  /** Через сколько шагов генератор начинает повторять сам себя. */
  function длинаКруга(шаг, потолок) {
    const виденные = new Set();
    for (let i = 0; i < потолок; i++) {
      const з = шаг();
      if (виденные.has(з)) return виденные.size;
      виденные.add(з);
    }
    return -1;   // за отведённое число шагов повтора не встретили
  }

  /** Сколько разных значений принимает младший байт выданной доли. */
  function разныхМладшихБайтов(доля, сколько) {
    const набор = new Set();
    for (let i = 0; i < сколько; i++) набор.add(Math.floor(доля() * 4294967296) & 255);
    return набор.size;
  }

  /**
   * Насколько ровно ложится бросок «выбери одно из 36» — ровно так игра
   * и тасует колоду. Хи-квадрат — одно число, показывающее перекос.
   * Для 36 вариантов нормальное значение около 35; тысячи — это уже перекос.
   */
  function перекосБроска(доля, сколько) {
    const корзины = new Array(36).fill(0);
    for (let i = 0; i < сколько; i++) корзины[Math.min(35, Math.floor(доля() * 36))]++;
    const ожидание = сколько / 36;
    return корзины.reduce(function (с, н) { return с + (н - ожидание) * (н - ожидание) / ожидание; }, 0);
  }

  console.log('=== Самопроверка генератора случайных чисел ===\n');
  console.log('Мера 1. Через сколько шагов генератор начинает ходить по кругу');
  console.log('  (чем больше, тем лучше; смотрели не дальше 3 000 000 шагов)');
  for (const начало of [1, 777, 7930]) {
    const с = длинаКруга(старыйСломанный(начало), 3000000);
    const н = длинаКруга(состояниеНового(начало), 3000000);
    console.log('    зерно ' + String(начало).padStart(5) + ':  старый ' +
      String(с).padStart(9) + '   новый ' + (н === -1 ? 'больше 3 000 000' : String(н)));
  }

  console.log('\nМера 2. Сколько разных значений принимает младший байт выданного числа');
  console.log('  (из 256 возможных; чем меньше, тем беднее случайность)');
  console.log('    старый: ' + разныхМладшихБайтов(выходСтарого(1), 200000) +
    '   новый: ' + разныхМладшихБайтов(выходНового(1), 200000));

  console.log('\nМера 3. Перекос броска «выбери одно из 36» на 3 600 000 бросков');
  console.log('  (норма около 35, случайные разбросы дают до сотни; тысячи — перекос)');
  console.log('    старый: ' + перекосБроска(выходСтарого(1), 3600000).toFixed(1) +
    '   новый: ' + перекосБроска(выходНового(1), 3600000).toFixed(1));

  console.log('\nМера 4. Отдельные потоки не мешают друг другу');
  const потокА = создатьПоток(100);
  const потокБ = создатьПоток(100);
  const началоА = [потокА(), потокА(), потокА()];
  потокБ(); потокБ();                       // нарочно сдвигаем соседний поток
  const потокВ = создатьПоток(100);
  const повторВ = [потокВ(), потокВ(), потокВ()];
  const потокиЧестные = началоА.every(function (з, i) { return з === повторВ[i]; });
  console.log('    ' + (потокиЧестные
    ? 'да: два потока с одним зерном дают одни и те же числа, и вызовы соседа их не сдвигают'
    : 'НЕТ — потоки влияют друг на друга, повторить прогон нельзя!'));

  console.log('\nМера 5. Повторимость: то же зерно — те же числа?');
  поставитьЗерно(4242);
  const первыйРаз = [следующее(), следующее(), следующее()];
  поставитьЗерно(4242);
  const второйРаз = [следующее(), следующее(), следующее()];
  const совпало = первыйРаз.every(function (з, i) { return з === второйРаз[i]; });
  console.log('    ' + (совпало ? 'да, совпадает полностью' : 'НЕТ — повторить раздачу нельзя!'));

  process.exit(совпало && потокиЧестные ? 0 : 1);
}
