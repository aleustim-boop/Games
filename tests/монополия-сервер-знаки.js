/* Выдуманный токен: с настоящим токеном бота ничего общего. */
const ТОКЕН_ДЛЯ_ПРОБЫ = '1234567:VYDUMANNYY-TOKEN-DLYA-PROVERKI-monopolii-znakov';

function доводПосле(имя) {
  const где = process.argv.indexOf(имя);
  return где !== -1 ? process.argv[где + 1] : null;
}

/* =====================================================================
   РЕЖИМ «--сломать»: копия с порчей, прогон проверки на ней
   ===================================================================== */

const СТРОКА_ПОРЧИ = 'этоЗнак: Знаки.этоЗнак,';
const ЗАМЕНА_ПОРЧИ = 'этоЗнак: () => false,';

/** Скопировать server/ и js/ во временную папку (без данных игроков). */
function сделатьКопию(папка) {
  for (const часть of ['server', ...require('./пути-проекта.js').папкиКода()]) {
    fs.cpSync(path.join(ПРОЕКТ, часть), path.join(папка, часть), {
      recursive: true,
      filter: function (откуда) {
        const имя = path.basename(откуда);
        return имя !== 'данные' && имя !== 'node_modules';
      }
    });
  }
}

function сломать() {
  console.log('=== Ломающий прогон знаков монополии: сервер разучился узнавать номера — В и Д обязаны покраснеть ===');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'монополия-знаки-лом-'));
  try {
    сделатьКопию(папка);
    const файл = path.join(папка, 'server', 'игры', 'монополия.js');
    const текст = fs.readFileSync(файл, 'utf8');
    if (текст.indexOf(СТРОКА_ПОРЧИ) === -1) {
      console.log('ПРОВАЛ: строка «' + СТРОКА_ПОРЧИ + '» в копии монополия.js не нашлась — портить нечего');
      process.exitCode = 1;
      return;
    }
    fs.writeFileSync(файл, текст.replace(СТРОКА_ПОРЧИ, ЗАМЕНА_ПОРЧИ), 'utf8');
    console.log('Порченая копия: ' + папка);

    const прогон = spawnSync(process.execPath, [__filename, '--корень', папка], {
      encoding: 'utf8', timeout: 60000
    });
    const вывод = (прогон.stdout || '') + (прогон.stderr || '');
    console.log('\n----- вывод ломающего прогона -----\n' + вывод);
    console.log('------------------------------------');
    const покраснелаВ = /ПРОВАЛ \[В\]/.test(вывод);
    const покраснелаД = /ПРОВАЛ \[Д\]/.test(вывод);
    if (покраснелаВ && покраснелаД && прогон.status === 1) {
      console.log('красная, как надо: буквы В и Д покраснели, код выхода ' + прогон.status);
      process.exitCode = 0;
    } else {
      console.log('ПРОВАЛ: ждали красные В и Д, получили код выхода ' + прогон.status +
        ', покраснела В: ' + покраснелаВ + ', покраснела Д: ' + покраснелаД);
      process.exitCode = 1;
    }
  } finally {
    fs.rmSync(папка, { recursive: true, force: true });
    console.log('Временная копия убрана: ' + папка);
  }
}

