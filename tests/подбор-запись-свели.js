function разобрать(текст) {
  try { return JSON.parse(текст || '{}') || {}; } catch (сбой) { return {}; }
}

/** POST. «терпениеМс» — сколько ждать, потом обрываем сами (для длинного опроса). */
function спросить(путь, тело, терпениеМс) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    let закончено = false;
    const запрос = http.request({
      host: ХОЗЯИН_АДРЕС, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        if (закончено) return;
        закончено = true;
        clearTimeout(сторож);
        готово({ код: ответ.statusCode, тело: разобрать(текст), оборван: false });
      });
    });
    const сторож = терпениеМс ? setTimeout(function () {
      if (закончено) return;
      закончено = true;
      запрос.destroy();
      готово({ код: 0, тело: {}, оборван: true });
    }, терпениеМс) : null;
    запрос.on('error', function (сбой) {
      if (закончено) return;
      закончено = true;
      clearTimeout(сторож);
      беда(сбой);
    });
    запрос.write(данные);
    запрос.end();
  });
}

function сколькоКомнат() {
  return new Promise(function (готово, беда) {
    http.get({ host: ХОЗЯИН_АДРЕС, port: ПОРТ, path: encodeURI('/здоровье') }, function (ответ) {
      let текст = '';
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () { готово(разобрать(текст).комнат); });
    }).on('error', беда);
  });
}

/** Встать в очередь дурака. «доп» — метка страницы, переводной, тихий повтор. */
function встать(номер, имя, доп) {
  return спросить('/подбор', Object.assign(
    { initData: подписьИгрока(номер, имя), переводной: false }, доп || {}));
}

/** Один короткий опрос: ждущему ответ не придёт — обрываем через 3 с. */
function опрос(ключ) {
  return спросить('/подбор-новости', { ключОжидания: ключ }, 3000);
}

function кнопкаБота(номер, имя, ключ) {
  return спросить('/подбор-с-ботом', { initData: подписьИгрока(номер, имя), ключОжидания: ключ });
}

function выйти(место) {
  return спросить('/выйти', { код: место.код, пропуск: место.пропуск });
}

function состояние(место) {
  return спросить('/состояние', { код: место.код, пропуск: место.пропуск });
}

function простоСвели(ответ) {
  return ответ.код === 200 && ответ.тело.статус === 'свели' &&
    Boolean(ответ.тело.код) && Boolean(ответ.тело.пропуск);
}

function ждёт(ответ) {
  return ответ.код === 200 && ответ.тело.статус === 'ждёт' && !ответ.тело.код &&
    typeof ответ.тело.ключОжидания === 'string' && ответ.тело.ключОжидания.length > 10;
}

function отменить(ответ) {
  if (ответ && ответ.тело && ответ.тело.ключОжидания) {
    return спросить('/подбор-отмена', { ключОжидания: ответ.тело.ключОжидания });
  }
  return Promise.resolve();
}

/** Свести пару: первый ждёт, второй встаёт и сразу получает место. */
async function свестиПару(первый, второй, доп1, доп2) {
  const ждал = await встать(первый.номер, первый.имя, доп1);
  const пришёл = await встать(второй.номер, второй.имя, доп2);
  return { ждал: ждал, пришёл: пришёл };
}

