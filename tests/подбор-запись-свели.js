/* 4) Потерянные ответы: повтор находит то же место. */
async function потерянныеОтветы() {
  console.log('4. Потерянные ответы — повтор отдаёт то же место');
  const КОСТЯ = { номер: 509, имя: 'Костя' }, ЛЁВА = { номер: 510, имя: 'Лёва' };
  const МЕТКА_КОСТИ = 'kostya-vkladka-1', МЕТКА_ЛЁВЫ = 'lyova-vkladka-1';
  const было = await сколькоКомнат();
  const пара = await свестиПару(КОСТЯ, ЛЁВА, { метка: МЕТКА_КОСТИ }, { метка: МЕТКА_ЛЁВЫ });
  проверить(ждёт(пара.ждал) && простоСвели(пара.пришёл), 'Костя ждал, Лёва встал и сведён с ним');

  // Ответ /подбор Лёвы «потерялся»: тихий повтор той же страницы.
  const повторЛёвы = await встать(ЛЁВА.номер, ЛЁВА.имя, { метка: МЕТКА_ЛЁВЫ, повтор: true });
  проверить(простоСвели(повторЛёвы) && повторЛёвы.тело.код === пара.пришёл.тело.код &&
    повторЛёвы.тело.пропуск === пара.пришёл.тело.пропуск,
    'тихий повтор /подбор Лёвы отдал то же место и тот же пропуск');
  // Явное нажатие той же страницы — тоже то же место, не новая очередь.
  const нажатиеЛёвы = await встать(ЛЁВА.номер, ЛЁВА.имя, { метка: МЕТКА_ЛЁВЫ });
  проверить(простоСвели(нажатиеЛёвы) && нажатиеЛёвы.тело.код === пара.пришёл.тело.код,
    'Лёва ещё раз нажал поиск, сидя за столом, — тот же стол');

  // Ответ опроса Кости «потерялся»: клиент спрашивает опрос снова, затем тихий повтор.
  const потерянный = await опрос(пара.ждал.тело.ключОжидания);
  проверить(простоСвели(потерянный) && потерянный.тело.код === пара.пришёл.тело.код,
    'опрос Кости отдал место (ответ «потерялся»)');
  const повторОпроса = await опрос(пара.ждал.тело.ключОжидания);
  проверить(повторОпроса.тело.статус === 'не_найдено' || (простоСвели(повторОпроса) &&
    повторОпроса.тело.код === пара.пришёл.тело.код),
    'повторный опрос Кости не завис и не выдал чужого стола');
  const повторКости = await встать(КОСТЯ.номер, КОСТЯ.имя, { метка: МЕТКА_КОСТИ, повтор: true });
  проверить(простоСвели(повторКости) && повторКости.тело.код === пара.пришёл.тело.код &&
    повторКости.тело.пропуск === потерянный.тело.пропуск,
    'тихий повтор /подбор Кости отдал то же место и тот же пропуск — Костя не потерялся');
  проверить((await сколькоКомнат()) === было + 1, 'после всех повторов — одна комната');
  const глазамиЛёвы = await состояние(пара.пришёл.тело);
  проверить(Boolean(глазамиЛёвы.тело.состояние) && глазамиЛёвы.тело.состояние.соперникПришёл === true,
    'Лёва видит соперника за столом');
}

