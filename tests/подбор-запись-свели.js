  const второе = await встать(ИГОРЬ.номер, ИГОРЬ.имя, { метка: 'igor-ustr-2', переводной: true });
  проверить(ждёт(первое) && ждёт(второе), 'у Игоря две ждущие записи: подкидной и переводной');
  await ждатьШестьМинут([первое.тело.ключОжидания, второе.тело.ключОжидания]);
  const живо = await Promise.all([короткийОпрос(первое.тело.ключОжидания), короткийОпрос(второе.тело.ключОжидания)]);
  проверить(живо[0].оборван === true && живо[1].оборван === true,
    'через 6 минут опросов обе записи Игоря ещё ждут (подмена часов сработала как надо)');

