/* Красные строки консоли. Одну прощаем нарочно: настоящий скрипт
   telegram.org мы сами не пускаем на страницу (иначе он затрёт подделку),
   и браузер честно жалуется на неудавшуюся загрузку. Это наша работа,
   а не поломка игры. */
function ловецОшибок(страница) {
  const красные = [];
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const текст = м.text();
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js/.test(текст + ' ' + откуда)) return;
    красные.push('консоль: ' + текст + (откуда ? ' [' + откуда + ']' : ''));
  });
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  return красные;
}

/** Что видно про экран прямо сейчас — одним куском. */
async function снятьПоказания(страница) {
  return страница.evaluate(() => {
    const корень = document.documentElement.style;
    const п = window.ПоддельныйТелеграм;
    return {
      журнал: (п && п.журнал ? п.журнал.slice() : []),
      просилиРаз: window.__дневник ? window.__дневник.полныйЭкран : -1,
      цветШапки: window.__дневник ? window.__дневник.цветШапки : '',
      цветФона: window.__дневник ? window.__дневник.цветФона : '',
      состояние: window.Телеграм ? window.Телеграм.состояние() : null,
      вПолном: window.Телеграм ? window.Телеграм.вПолномЭкране() : null,
      края: {
        сверху: корень.getPropertyValue('--безопасно-сверху'),
        снизу: корень.getPropertyValue('--безопасно-снизу'),
        слева: корень.getPropertyValue('--безопасно-слева'),
        справа: корень.getPropertyValue('--безопасно-справа')
      }
    };
  });
}

/**
 * Цвет, как его написал браузер, → «#rrggbb».
 * Браузер отвечает по-разному: «rgb(20, 83, 45)», «rgba(…)» и — когда цвет
 * посчитан через color-mix — «color(srgb 0.09 0.19 0.18)». Понимаем все три,
 * иначе стенд сравнивал бы строку со строкой и краснел на ровном месте.
 */
function вШестнадцатеричный(значение) {
  const текст = String(значение || '').trim();
  const вДва = (ч) => {
    const н = Math.max(0, Math.min(255, Math.round(ч)));
    return (н < 16 ? '0' : '') + н.toString(16);
  };
  let м = /^rgba?\((\d+),\s*(\d+),\s*(\d+)/.exec(текст);
  if (м) return '#' + вДва(+м[1]) + вДва(+м[2]) + вДва(+м[3]);
  м = /^color\(srgb\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)/.exec(текст);
  if (м) return '#' + вДва(+м[1] * 255) + вДва(+м[2] * 255) + вДва(+м[3] * 255);
  return '';
}

/** Порядок в журнале: раньше ли «что» случилось, чем «чего». */
function раньше(журнал, что, чего) {
  const а = журнал.indexOf(что);
  const б = журнал.indexOf(чего);
  return а !== -1 && б !== -1 && а < б;
}

