/* =====================================================================
   СЛОВА О ТОМ, КАК СЧИТАЮТСЯ ОЧКИ, — В СОГЛАСИИ С СЕРВЕРОМ.

   Зачем. На экране «Рейтинг» есть пояснение (список ПРАВИЛА_ОЧКОВ в
   общее/js/рейтинг-экран.js). Числа в нём вписаны руками, а настоящие живут в
   server/рейтинг.js (ЦЕНА и потолок ботов). Они разошлись молча: экран
   обещал «сложный бот — 6», а сервер платил 2. Эта проверка сверяет их
   при каждом прогоне.

   ЧТО ПРОВЕРЯЕМ (числа берём из сервера, а не из головы):
     1) список ПРАВИЛА_ОЧКОВ найден и разобран;
     2) победа и ничья с человеком, победа над ботом каждого уровня,
        ничья с ботом — число в строке равно серверному («очков не даёт»
        значит ноль);
     3) потолок очков от ботов в сутки — то же число, и сказано, что он
        один на все игры;
     4) правило стола на несколько человек на месте (за тех, кто
        закончил хуже; за других победителей очков нет);
     5) правило игры пара на пару на месте (очки только за соперников,
        за напарника — нет; решение владельца 30.09 09:31), и сервер
        правда платит за напарника 0 — меряем прогоном партии;
     6) во всём списке нет числа, которого нет на сервере.
   Не нашли строку или число на сервере — это ПРОВАЛ, а не пропуск.

   Боевых данных не касается: для прогона партии папка данных
   (GAMES_DATA) уводится во временную ДО подключения сервера.

   УМЕЕТ КРАСНЕТЬ (две порчи):
     node tests/рейтинг-правила-очков-слова.js --сломать <путь к копии>
   читает экран из копии общее/js/рейтинг-экран.js, а не из проекта. Копию
   делают заранее во временной папке и портят в ней (например, возвращают
   «сложный бот — 6 очков» или убирают строку про пары): прогон на ней
   обязан провалиться.
     node tests/рейтинг-правила-очков-слова.js --сломать-сервер
   копирует server/ (без server/данные) и общее/js/игры-реестр.js во временную
   папку системы, в КОПИИ server/рейтинг.js возвращает старое правило
   (за напарника половина цены) — слова «за напарника — нет» перестают
   быть правдой, прогон обязан провалиться.
   Файлы проекта проверка не трогает.

   Запуск: node tests/рейтинг-правила-очков-слова.js   Выход 0 — провалов нет.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const vm = require('vm');

const ПРОЕКТ = path.join(__dirname, '..');
const гдеЛомать = process.argv.indexOf('--сломать');
const ЛОМАТЬ = гдеЛомать !== -1;
const ЛОМАТЬ_СЕРВЕР = process.argv.indexOf('--сломать-сервер') !== -1;

let всегоПроверок = 0;
let провалов = 0;
function проверить(что, условие, подробности) {
  всегоПроверок++;
  if (условие) { console.log('  ок     ' + что); return; }
  провалов++;
  console.log('  ПРОВАЛ ' + что + (подробности ? ': ' + подробности : ''));
}

/** Откуда читать экран: из проекта или из испорченной копии. */
function путьКЭкрану() {
  if (!ЛОМАТЬ) return path.join(ПРОЕКТ, 'общее', 'js', 'рейтинг-экран.js');
  const названный = process.argv[гдеЛомать + 1];
  if (!названный || названный.indexOf('--') === 0) {
    console.log('С --сломать нужен путь к копии общее/js/рейтинг-экран.js во временной папке.');
    process.exit(2);
  }
  const абсолютный = path.resolve(названный);
  if (абсолютный.indexOf(path.resolve(ПРОЕКТ) + path.sep) === 0) {
    console.log('Ломать можно только копию вне проекта, а не файл проекта: ' + абсолютный);
    process.exit(2);
  }
  return абсолютный;
}

/** Заменить ровно одно вхождение, иначе приём порчи устарел — сказать вслух. */
function заменитьРовноОдин(файл, старое, новое) {
  const части = fs.readFileSync(файл, 'utf8').split(старое);
  if (части.length !== 2) {
    throw new Error('приём порчи устарел: «' + старое + '» встречается в ' + файл + ' ' +
      (части.length - 1) + ' раз(а) вместо одного — поправьте проверку тем же коммитом');
  }
  fs.writeFileSync(файл, части.join(новое), 'utf8');
}

/* Старое правило (до 30.09) словами кода: напарник проходит ограничитель
   сговора и приносит половину цены. Вставляется в КОПИЮ вместо пропуска. */
const СТАРОЕ_ПРАВИЛО_НАПАРНИКА =
  'if (этоНапарник) {\n' +
  '        /* ИСПОРЧЕНО --сломать-сервер: за напарника снова половина цены, как до 30.09 */\n' +
  '        if (параЕщёВЗачёте(запись, другой.номер, сегодня)) {\n' +
  "          const заНапарника = начислить(запись, 'человек', Math.floor(ценаСоперника(другой, исход) * 0.5), сегодня);\n" +
  '          добавлено[игрок.номер] += заНапарника;\n' +
  '          if (половина) половина.очки += заНапарника;\n' +
  '          половинаСостава.очки += заНапарника;\n' +
  '        }\n' +
  '        continue;\n' +
  '      }';

/** Откуда брать сервер: из проекта или из испорченной копии во временной папке. */
function папкаСервера() {
  if (!ЛОМАТЬ_СЕРВЕР) return ПРОЕКТ;
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'рейтинг-слова-сломать-сервер-'));
  // Боевые данные в копию не везём — они не нужны и не наши.
  fs.cpSync(path.join(ПРОЕКТ, 'server'), path.join(папка, 'server'), {
    recursive: true,
    filter: function (откуда) {
      const имя = path.basename(откуда);
      return имя !== 'данные' && имя !== 'node_modules';
    }
  });
  require('./пути-проекта.js').создатьПапкиКода(папка);
  fs.copyFileSync(path.join(ПРОЕКТ, 'общее', 'js', 'игры-реестр.js'), path.join(папка, 'общее', 'js', 'игры-реестр.js'));
  заменитьРовноОдин(path.join(папка, 'server', 'рейтинг.js'), 'if (этоНапарник) continue;', СТАРОЕ_ПРАВИЛО_НАПАРНИКА);
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: сервер из испорченной копии ' + папка + ' — прогон обязан провалиться ***\n');
  return папка;
}

/** Достать список строк ПРАВИЛА_ОЧКОВ из текста экрана; не нашли — null. */
function списокПравил(текстЭкрана) {
  const начало = текстЭкрана.indexOf('const ПРАВИЛА_ОЧКОВ = [');
  if (начало === -1) return null;
  const открыть = текстЭкрана.indexOf('[', начало);
  const закрыть = текстЭкрана.indexOf('\n  ];', открыть);
  if (закрыть === -1) return null;
  // В списке только строки и «+» между ними — выполнять в песочнице безопасно.
  const литерал = текстЭкрана.slice(открыть, закрыть + 4);
  try {
    const список = vm.runInNewContext('(' + литерал + ')', {}, { timeout: 1000 });
    return Array.isArray(список) ? список : null;
  } catch (ошибка) {
    return null;
  }
}

/** Одна строка списка, подходящая под образец; иначе null (и провал). */
function найтиСтроку(список, образец, названиеДляОтчёта) {
  const подходят = список.filter(function (строка) { return образец.test(строка); });
  проверить('в списке ровно одна строка «' + названиеДляОтчёта + '»',
    подходят.length === 1, 'найдено строк: ' + подходят.length);
  return подходят.length === 1 ? подходят[0] : null;
}

/** Число очков, названное строкой: «10 очков» -> 10, «очков не даёт» -> 0. */
function очкиВСтроке(строка) {
  const числа = строка.match(/\d+/g) || [];
  if (числа.length === 1) return Number(числа[0]);
  if (числа.length === 0 && /очков не даёт/.test(строка)) return 0;
  return null;
}

function сверить(список, образец, названиеДляОтчёта, ожидаемое) {
  const строка = найтиСтроку(список, образец, названиеДляОтчёта);
  if (строка === null) return;
  проверить(названиеДляОтчёта + ': на сервере ' + ожидаемое + ', в словах ' + очкиВСтроке(строка),
    очкиВСтроке(строка) === ожидаемое, 'строка: «' + строка + '»');
}

/* --- Сервер: настоящие числа --- */
console.log('Числа с сервера (server/рейтинг.js)');
const СЕРВЕР = папкаСервера();
// Прогон партии пишет на диск — уводим папку данных ДО подключения сервера.
process.env.GAMES_DATA = fs.mkdtempSync(path.join(os.tmpdir(), 'рейтинг-слова-данные-'));
const рейтинг = require(path.join(СЕРВЕР, 'server', 'рейтинг.js'));
const ЦЕНА = рейтинг.ЦЕНА;
const ПОТОЛОК = рейтинг.ПОТОЛОК_ОТ_БОТОВ_В_СУТКИ;
проверить('сервер отдаёт таблицу цен ЦЕНА со всеми уровнями',
  Boolean(ЦЕНА && ЦЕНА.человек && ЦЕНА.сложный && ЦЕНА.обычный && ЦЕНА['лёгкий']));
проверить('сервер отдаёт суточный потолок ботов числом', Number.isInteger(ПОТОЛОК) && ПОТОЛОК > 0,
  'получили: ' + ПОТОЛОК);
if (!(ЦЕНА && ЦЕНА.человек && ЦЕНА.сложный && ЦЕНА.обычный && ЦЕНА['лёгкий']) ||
    !Number.isInteger(ПОТОЛОК)) {
  console.log('\nБез серверных чисел сверять нечего — это провал.');
  console.log('Итого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
  process.exit(1);
}
console.log('  человек: победа ' + ЦЕНА.человек.победа + ', ничья ' + ЦЕНА.человек.ничья +
  '; сложный ' + ЦЕНА.сложный.победа + ', обычный ' + ЦЕНА.обычный.победа +
  ', лёгкий ' + ЦЕНА['лёгкий'].победа + '; ничья с ботом ' + ЦЕНА.сложный.ничья +
  '; потолок ботов ' + ПОТОЛОК);

/* --- Экран: слова --- */
const файлЭкрана = путьКЭкрану();
console.log('\nСлова на экране (' + файлЭкрана + ')' + (ЛОМАТЬ ? '  [ломающий запуск]' : ''));
let текстЭкрана = '';
try {
  текстЭкрана = fs.readFileSync(файлЭкрана, 'utf8');
} catch (ошибка) {
  проверить('файл экрана читается', false, ошибка.message);
}
const список = списокПравил(текстЭкрана);
проверить('список ПРАВИЛА_ОЧКОВ найден и разобран', Array.isArray(список) && список.length > 0);

if (Array.isArray(список) && список.length > 0) {
  // Ничья с ботом на сервере у всех уровней одна: иначе одной строкой её не описать.
  const ничьиБотов = [ЦЕНА.сложный.ничья, ЦЕНА.обычный.ничья, ЦЕНА['лёгкий'].ничья];
  проверить('ничья с ботом на сервере одинакова у всех уровней (иначе слова придётся делить)',
    ничьиБотов.every(function (число) { return число === ничьиБотов[0]; }),
    'на сервере: ' + ничьиБотов.join(', '));

  сверить(список, /^победа над живым человеком/, 'победа над человеком', ЦЕНА.человек.победа);
  сверить(список, /^ничья с живым человеком/, 'ничья с человеком', ЦЕНА.человек.ничья);
  сверить(список, /^победа над сложным ботом/, 'победа над сложным ботом', ЦЕНА.сложный.победа);
  сверить(список, /^победа над обычным ботом/, 'победа над обычным ботом', ЦЕНА.обычный.победа);
  сверить(список, /^победа над лёгким ботом/, 'победа над лёгким ботом', ЦЕНА['лёгкий'].победа);
  сверить(список, /^ничья с ботом/, 'ничья с ботом', ничьиБотов[0]);

  const потолок = найтиСтроку(список, /^С ботов можно набрать/, 'потолок очков от ботов');
  if (потолок !== null) {
    проверить('потолок ботов: на сервере ' + ПОТОЛОК + ', в словах ' + очкиВСтроке(потолок),
      очкиВСтроке(потолок) === ПОТОЛОК, 'строка: «' + потолок + '»');
    проверить('про потолок сказано, что он общий на все игры', /во всех играх вместе/.test(потолок));
    проверить('про потолок сказано «в сутки»', /в сутки/.test(потолок));
  }

  const стол = найтиСтроку(список, /^За столом на несколько человек/, 'правило стола на несколько человек');
  if (стол !== null) {
    проверить('про стол: очки — за каждого, кто закончил хуже', /за каждого, кто закончил хуже/.test(стол));
    проверить('про стол: за другими победителями очков нет', /за других победителей очков нет/.test(стол));
  }

  const пары = найтиСтроку(список, /^В игре пара на пару/, 'правило игры пара на пару');
  if (пары !== null) {
    проверить('про пары: очки только за соперников', /только за соперников/.test(пары), 'строка: «' + пары + '»');
    проверить('про пары: за напарника — нет', /за напарника — нет/.test(пары), 'строка: «' + пары + '»');
    /* Слова обещают ноль за напарника — меряем, что сервер правда так
       платит. Пара обыграла двух лёгких ботов: весь итог сверх их цены —
       доля за напарника. Ничья вчетвером: сверх двух ничьих — тоже она. */
    const надБотами = рейтинг.учестьПартию('дурак', [
      { номер: 9101, имя: 'А', этоБот: false, победил: true, ничья: false, напарник: 9103 },
      { этоБот: true, уровень: 'лёгкий', победил: false, ничья: false },
      { номер: 9103, имя: 'Б', этоБот: false, победил: true, ничья: false, напарник: 9101 },
      { этоБот: true, уровень: 'лёгкий', победил: false, ничья: false }
    ]);
    const заНапарникаПобеда = надБотами[9101] - ЦЕНА['лёгкий'].победа * 2;
    проверить('сервер: за напарника при победе пары 0, как в словах (получили ' + заНапарникаПобеда + ')',
      заНапарникаПобеда === 0);
    const вничью = рейтинг.учестьПартию('дурак', [9201, 9202, 9203, 9204].map(function (номер, и, все) {
      return { номер: номер, имя: 'Н' + номер, этоБот: false, победил: false, ничья: true, напарник: все[(и + 2) % 4] };
    }));
    const заНапарникаНичья = вничью[9201] - ЦЕНА.человек.ничья * 2;
    проверить('сервер: за напарника при ничьей 0, как в словах (получили ' + заНапарникаНичья + ')',
      заНапарникаНичья === 0);
  }

  // Любое число в словах обязано быть числом сервера — иначе устарело.
  const серверные = new Set([ПОТОЛОК]);
  Object.keys(ЦЕНА).forEach(function (уровень) {
    серверные.add(ЦЕНА[уровень].победа);
    серверные.add(ЦЕНА[уровень].ничья);
  });
  const лишние = [];
  список.forEach(function (строка) {
    (строка.match(/\d+/g) || []).forEach(function (число) {
      if (!серверные.has(Number(число))) лишние.push(число + ' в «' + строка + '»');
    });
  });
  проверить('во всех словах нет чисел, которых нет на сервере', лишние.length === 0, лишние.join('; '));
}

console.log('\nИтого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
process.exit(провалов > 0 ? 1 : 0);
