    const д = страницаКакНарды();
    const плашка = д.getElementById('кнопка-вернуться-в-игру');
    const стенд = поднятьМодуль(д);
    стенд.окно.ОнлайнЛобби.подключить(НАРДЫ);
    const лобби = д.getElementById('экран-лобби');
    надо(д.getElementById('кнопка-вернуться-в-игру') === плашка, 'плашка — тот же узел, не копия');
