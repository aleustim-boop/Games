/* ---------- Какой модуль проверяем ---------- */

function довод(имя) {
  const с = process.argv.filter(function (а) { return а.indexOf('--' + имя + '=') === 0; })[0];
  return с ? с.slice(имя.length + 3) : null;
}

const ломаем = process.argv.indexOf('--сломать') !== -1;
let путьМодуля = довод('модуль') || ПУТЬ_МОДУЛЯ;

if (ломаем) {
  // Копия без переноса плашки: тело поставитьПлашкуВозврата сразу выходит.
  const исходник = fs.readFileSync(ПУТЬ_МОДУЛЯ, 'utf8');
  const было = 'function поставитьПлашкуВозврата() {';
  if (исходник.indexOf(было) === -1) {
    console.log('Не смогла сломать: в модуле нет «' + было + '» — проверка устарела.');
    process.exit(1);
  }
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'онлайн-лобби-'));
  путьМодуля = path.join(папка, 'онлайн-лобби.js');
  fs.writeFileSync(путьМодуля, исходник.replace(было, было + ' return false;'));
  console.log('Ломающий запуск: копия без переноса плашки — ' + путьМодуля);
}

const МОДУЛЬ = fs.readFileSync(путьМодуля, 'utf8');

/* ---------- id комнаты-05 из index.html ---------- */

function idКомнатыИзIndex() {
  const страница = fs.readFileSync(path.join(КОРЕНЬ, 'index.html'), 'utf8');
  const начало = страница.indexOf('<section id="экран-комнаты"');
  const конец = начало === -1 ? -1 : страница.indexOf('</section>', начало);
  if (начало === -1 || конец === -1) return [];
  const кусок = страница.slice(начало, конец);
  const ids = [];
  const правило = /\sid="([^"]+)"/g;
  let н;
  while ((н = правило.exec(кусок))) ids.push(н[1]);
  return ids;
}

/* ---------- Помощники поддельной страницы ---------- */

function всеУзлы(корень, список) {
  список = список || [];
  for (const д of корень.children || []) { список.push(д); всеУзлы(д, список); }
  return список;
}

function сколькоId(документ, id) {
  return всеУзлы(документ.documentElement).filter(function (у) { return у.id === id; }).length;
}

/** Лобби: верхняя строка, потом карточки. */
function сделатьЛобби(д) {
  return д.узел('section', { id: 'экран-лобби', класс: 'экран' },
    д.узел('div', { класс: 'верх-игры' }, д.узел('button', { текст: '‹' })),
    д.узел('h1', { класс: 'лобби__заголовок', текст: 'Нарды' }),
    д.узел('button', { id: 'лобби-найти-игру', текст: 'Играть онлайн' }));
}

/** Страница как нарды сейчас: плашка на экране друга, старая комната с кодом. */
function страницаКакНарды() {
  const д = сделатьДокумент();
  д.body.appendChild(сделатьЛобби(д));
  д.body.appendChild(д.узел('section', { id: 'экран-друга', класс: 'экран' },
    д.узел('button', { id: 'кнопка-вернуться-в-игру', класс: 'кнопка кнопка--возврат скрыт', текст: 'Вернуться к игре с другом' })));
  д.body.appendChild(д.узел('section', { id: 'экран-комнаты', класс: 'экран' },
    д.узел('h2', { класс: 'заголовок', текст: 'Код игры' }),
    д.узел('div', { id: 'код-комнаты', класс: 'код-игры', текст: '····' }),
    д.узел('button', { id: 'кнопка-копировать-код', класс: 'кнопка', текст: 'Скопировать код' }),
    д.узел('button', { id: 'кнопка-комната-отмена', класс: 'кнопка кнопка--мелкая', текст: 'Отменить игру' })));
  return д;
}

function поднятьМодуль(документ, добавки) {
  const стенд = поднять(МОДУЛЬ, { документ: документ, имяФайла: 'js/онлайн-лобби.js' });
  Object.assign(стенд.окно, добавки || {});
  Object.assign(стенд.песочница, добавки || {});
  return стенд;
}

const НАРДЫ = { игра: 'нарды', мест: { мин: 2, макс: 2, обычно: 2 }, создание: 'сразу' };

