function запрещённыйАдрес(адрес) {
  const низ = адрес.toLowerCase();
  if (низ.indexOf('.env') !== -1) return true;
  const части = низ.split(/[\\/]/).filter(Boolean);
  if (части.length && части[0] === 'bot') return true;
  return части.some((часть) => часть.charAt(0) === '.');
}

function поднятьСервер(порт) {
  return new Promise((готово) => {
    const сервер = http.createServer((запрос, ответ) => {
      let адрес;
      try {
        адрес = decodeURIComponent(запрос.url.split('?')[0]);
      } catch (ошибка) {
        ответ.writeHead(400); ответ.end('непонятный адрес'); return;
      }
      if (адрес === '/') адрес = '/index.html';
      if (запрещённыйАдрес(адрес)) { ответ.writeHead(403); ответ.end('доступ закрыт'); return; }

      const относительный = адрес.replace(/^\/+/, '');
      const файл = path.join(КОРЕНЬ, относительный);
      if (файл !== КОРЕНЬ && !файл.startsWith(КОРЕНЬ + path.sep)) {
        ответ.writeHead(403); ответ.end('доступ закрыт: файл вне папки проекта'); return;
      }

      fs.readFile(файл, (ошибка, данные) => {
        if (ошибка) { ответ.writeHead(404); ответ.end('не найдено: ' + адрес); return; }
        ответ.writeHead(200, {
          'Content-Type': ТИПЫ_ФАЙЛОВ[path.extname(файл).toLowerCase()] || 'application/octet-stream',
          'Cache-Control': 'no-store'
        });
        ответ.end(данные);
      });
    });
    сервер.listen(порт, АДРЕС_ХОЗЯИНА, () => готово(сервер));
  });
}

/* ---------------------------------------------------------------------
   ЛОМАЮЩИЙ РЕЖИМ: испорченная копия style.css во временном файле.
   Добавка правила с тем же селектором в конец файла — по source order
   она побеждает моё же правило (равная специфичность), не нужно ловить
   точный кусок текста, который сосед мог сдвинуть на строку.

   ВАЖНО (найдено диагностикой 25.09): в style.css у карточки «Моё место»
   есть ДВА правила с «margin: auto 0 0» разной специфичности — базовое
   «#экран-рейтинга-игроков > #рейтинг-моё-место» (строка ~12078) и более
   специфичное «…:not(.подпись)» (строка ~16693, добавлено отдельно ради
   «position: relative» для не-подписи). Именно ВТОРОЕ, более специфичное,
   правило решает исход для обычной карточки — по CSS specificity оно
   побеждает первое независимо от порядка в файле. Поэтому порча с
   селектором БЕЗ «:not(.подпись)» проигрывает ему по специфичности и
   реального провала не даёт (проверено: getComputedStyle показывал
   «margin-top: auto» как ни в чём не бывало). Порча должна целиться
   в селектор той же (или большей) специфичности — «:not(.подпись)» —
   тогда оно побеждает по source order, как и задумано.
   --------------------------------------------------------------------- */

function убедитьсяЧтоЕсть(текст, кусок, метка) {
  if (текст.indexOf(кусок) === -1) {
    throw new Error('Поломка «' + метка + '»: в style.css не нашёлся кусок «' + кусок + '» — ' +
      'похоже, правило переименовали или удалили, поломку нужно поправить вслед за ним.');
  }
}

