const ШИРИНЫ = [{ width: 390, height: 844 }, { width: 805, height: 1025 }, { width: 1280, height: 900 }];

async function запуститьПрогон(путьСломанногоCSS) {
  const порт = await выбратьСвободныйПорт();
  const сервер = await поднятьСервер(порт);
  const адрес = 'http://' + АДРЕС_ХОЗЯИНА + ':' + порт + '/index.html';
  let браузер = null;

  try {
    браузер = await chromium.launch();

    /* ---------- Короткий список: жалоба владельца, три ширины ---------- */
    for (const размер of ШИРИНЫ) {
      const метка = размер.width + '×' + размер.height;
      const { контекст, страница, красные } = await открытьРейтинг(браузер, адрес, размер, ответКороткий, путьСломанногоCSS);

      const низ = await замерНизаКарточки(страница);
      if (проверить(метка + ' (короткий): узлы найдены (карточка/вкладки/экран)',
        низ.экранЕсть && низ.карточкаЕсть && низ.вкладкиЕсть, JSON.stringify(низ))) {
        проверить(метка + ' (короткий): низ карточки у верха полосы вкладок (запас ' + низ.запас + 'px ±2px)',
          Math.abs(низ.зазор - низ.запас) <= 2,
          'зазор=' + Math.round(низ.зазор) + ', запас=' + низ.запас);
      }

      const надп = await замерНадписи(страница);
      проверить(метка + ' (короткий): карточка «Моё место» найдена', надп.карточкаЕсть, JSON.stringify(надп));
      проверить(метка + ' (короткий): подписи «Все игроки показаны» на экране нет (список докатывается сам)',
        !надп.надписьЕсть, JSON.stringify(надп));

      const путьСнимка = path.join(ПАПКА_СНИМКОВ, 'рейтинг-моё-место-короткий-' + размер.width + '.png');
      if (!сломать) {
        await страница.screenshot({ path: путьСнимка });
        проверить('снимок ' + path.basename(путьСнимка) + ' записан',
          fs.existsSync(путьСнимка) && fs.statSync(путьСнимка).size > 0, путьСнимка);
      }

      проверить(метка + ' (короткий): в консоли нет ошибок', красные.length === 0, красные.join(' | '));
      await контекст.close();
    }

    /* ---------- Длинный список: три ширины, поведение не должно измениться ---------- */
    for (const размер of ШИРИНЫ) {
      const метка = размер.width + '×' + размер.height;
      const { контекст, страница, красные } = await открытьРейтинг(браузер, адрес, размер, ответДлинный, путьСломанногоCSS);

      /* При scrollTop=0 у ДЕЙСТВИТЕЛЬНО длинного списка (контент выше
         карточки выше самой высоты экрана) карточка физически не видна —
         её natural-flow позиция в потоке ниже нижней границы вьюпорта,
         sticky начинает её держать только когда прокрутка «доносит» эту
         границу до низа. Это не баг: «видна прижатой уже на scrollTop=0»
         и «список достаточно длинный, чтобы скроллить» — взаимоисключающие
         условия (если бы карточка была видна без скролла, скроллить было
         бы нечего). Замер делаем ПОСЛЕ прокрутки до конца — тем же
         приёмом, что и в tests/снимок-рейтинг-эталон.js (замерыПрокрутки-
         ИНиза): это и есть настоящая проверка «длинный список не сломан». */
      await страница.evaluate(() => {
        const экран = document.getElementById('экран-рейтинга-игроков');
        if (экран) экран.scrollTop = экран.scrollHeight;
      });
      await страница.waitForTimeout(200);

      const низПослеПрокрутки = await замерНизаКарточки(страница);
      if (проверить(метка + ' (длинный, прокрутка до конца): узлы найдены (карточка/вкладки/экран)',
        низПослеПрокрутки.экранЕсть && низПослеПрокрутки.карточкаЕсть && низПослеПрокрутки.вкладкиЕсть, JSON.stringify(низПослеПрокрутки))) {
        проверить(метка + ' (длинный, прокрутка до конца): карточка приклеена к низу (запас ±2px), как и раньше',
          Math.abs(низПослеПрокрутки.зазор - низПослеПрокрутки.запас) <= 2,
          'зазор=' + Math.round(низПослеПрокрутки.зазор) + ', запас=' + низПослеПрокрутки.запас);
      }

      const посл = await замерПоследнейСтроки(страница);
      if (проверить(метка + ' (длинный, прокрутка до конца): узлы найдены (последняя строка/карточка)',
        посл.последняяЕсть && посл.карточкаЕсть, JSON.stringify(посл))) {
        проверить(метка + ' (длинный, прокрутка до конца): последняя строка целиком выше карточки',
          посл.последняяBottom <= посл.карточкаTop + 1,
          'последняя.bottom=' + Math.round(посл.последняяBottom) + ', карточка.top=' + Math.round(посл.карточкаTop));
      }

      if (!сломать && размер.width === 390) {
        const путьСнимка = path.join(ПАПКА_СНИМКОВ, 'рейтинг-моё-место-длинный-390.png');
        await страница.screenshot({ path: путьСнимка });
        проверить('снимок ' + path.basename(путьСнимка) + ' записан',
          fs.existsSync(путьСнимка) && fs.statSync(путьСнимка).size > 0, путьСнимка);
      }

      проверить(метка + ' (длинный): в консоли нет ошибок', красные.length === 0, красные.join(' | '));
      await контекст.close();
    }

    /* ---------- Доп. смоук-проверки на 390×844 ---------- */
    const РАЗМЕР_СМОУК = { width: 390, height: 844 };

    // «Друзья» без единого друга: карточка становится «.подпись» и НЕ должна
    // уезжать вниз (иначе регрессия того же рода, что чинили в рейтинг-на-пк.js).
    {
      const { контекст, страница, красные } = await открытьРейтинг(браузер, адрес, РАЗМЕР_СМОУК, ответКороткий, путьСломанногоCSS);
      await страница.click('[data-круг="друзья"]');
      await страница.waitForTimeout(300);
      const замер = await страница.evaluate(() => {
        const карточка = document.getElementById('рейтинг-моё-место');
        if (!карточка) return { карточкаЕсть: false };
        const r = карточка.getBoundingClientRect();
        return { карточкаЕсть: true, className: карточка.className, top: r.top };
      });
      if (проверить('390×844 (друзья пусто): карточка «Моё место» найдена', замер.карточкаЕсть, JSON.stringify(замер))) {
        проверить('390×844 (друзья пусто): карточка в состоянии «.подпись»',
          (' ' + замер.className + ' ').indexOf(' подпись ') !== -1,
          'className=' + замер.className);
        проверить('390×844 (друзья пусто): карточка НЕ уехала вниз (стоит в верхней половине экрана)',
          замер.top < РАЗМЕР_СМОУК.height / 2,
          'top=' + Math.round(замер.top) + ', половина высоты=' + (РАЗМЕР_СМОУК.height / 2));
      }
      проверить('390×844 (друзья пусто): в консоли нет ошибок', красные.length === 0, красные.join(' | '));
      await контекст.close();
    }

    // Новичок без очков: карточка «--новичок» — обычная карточка (не
    // «.подпись»), должна прижиматься к низу так же, как карточка с очками.
    {
      const { контекст, страница, красные } = await открытьРейтинг(браузер, адрес, РАЗМЕР_СМОУК, ответНовичок, путьСломанногоCSS);
      const низ = await замерНизаКарточки(страница);
      if (проверить('390×844 (новичок): узлы найдены', низ.экранЕсть && низ.карточкаЕсть && низ.вкладкиЕсть, JSON.stringify(низ))) {
        проверить('390×844 (новичок): карточка «--новичок», не «.подпись»',
          низ.className.indexOf('рейтинг__карточка--новичок') !== -1, 'className=' + низ.className);
        проверить('390×844 (новичок): карточка прижата к низу (запас ±2px)',
          Math.abs(низ.зазор - низ.запас) <= 2,
          'зазор=' + Math.round(низ.зазор) + ', запас=' + низ.запас);
      }
      проверить('390×844 (новичок): в консоли нет ошибок', красные.length === 0, красные.join(' | '));
      await контекст.close();
    }

    // Выбор одной игры («шашки») — новый ответ сервера перерисовывает
    // таблицу, карточка обязана остаться прижатой к низу.
    {
      const { контекст, страница, красные } = await открытьРейтинг(браузер, адрес, РАЗМЕР_СМОУК, ответКороткий, путьСломанногоCSS);
      await страница.click('#рейтинг-выбор-игры-кнопка');
      await страница.waitForSelector('#рейтинг-панель-игр:not(.скрыт)', { timeout: 5000 });
      await страница.click('#рейтинг-панель-игр-пункт-шашки');
      await страница.waitForTimeout(500);
      const кнопкаТекст = await страница.evaluate(() => {
        const к = document.getElementById('рейтинг-выбор-игры-кнопка');
        return к ? к.textContent.trim() : null;
      });
      проверить('390×844 (выбор игры): кнопка выбора игры показывает «Шашки»',
        Boolean(кнопкаТекст) && кнопкаТекст.indexOf('Шашки') !== -1, 'текст кнопки=' + кнопкаТекст);
      const низ = await замерНизаКарточки(страница);
      if (проверить('390×844 (выбор игры): узлы найдены после переключения', низ.экранЕсть && низ.карточкаЕсть && низ.вкладкиЕсть, JSON.stringify(низ))) {
        проверить('390×844 (выбор игры): карточка осталась прижатой к низу (запас ±2px)',
          Math.abs(низ.зазор - низ.запас) <= 2,
          'зазор=' + Math.round(низ.зазор) + ', запас=' + низ.запас);
      }
      проверить('390×844 (выбор игры): в консоли нет ошибок', красные.length === 0, красные.join(' | '));
      await контекст.close();
    }
  } finally {
    if (браузер) { try { await браузер.close(); } catch (е) { /* уже закрыт — не страшно */ } }
    await new Promise((р) => сервер.close(р));
  }
}

(async () => {
  let путьСломанногоCSS = null;
  try {
    if (!сломать) {
      console.log('=== Рейтинг: карточка «Моё место» внизу — ОБЫЧНЫЙ прогон ===\n');
    } else {
      console.log('=== Рейтинг: карточка «Моё место» внизу — ЛОМАЮЩИЙ прогон --сломать ===\n');
      console.log('Порчу копию style.css во временном файле: у карточки снова «margin-top: 2px»');
      console.log('(старое поведение до фикса) — короткий список должен провиснуть, длинный —');
      console.log('остаться зелёным (sticky-часть фикса не тронута).\n');

      const испорченный = создатьСломаннуюКопию();
      путьСломанногоCSS = path.join(os.tmpdir(), 'рейтинг-моё-место-внизу-сломанный-' + process.pid + '.css');
      fs.writeFileSync(путьСломанногоCSS, испорченный, 'utf8');
    }

    await запуститьПрогон(путьСломанногоCSS);
  } finally {
    if (путьСломанногоCSS && fs.existsSync(путьСломанногоCSS)) {
      try { fs.unlinkSync(путьСломанногоCSS); } catch (е) { /* временный файл, не страшно */ }
    }
  }

  console.log('');
  console.log('Итого проверок: ' + строкиОтчёта.length + ', провалов: ' + провалов);
  process.exit(провалов > 0 ? 1 : 0);
})().catch((ошибка) => {
  console.error('Проверка упала: ' + (ошибка && ошибка.stack || ошибка));
  process.exit(2);
});
