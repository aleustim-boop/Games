/** Низ карточки «Моё место» относительно верха полосы вкладок и её запас. */
async function замерНизаКарточки(страница) {
  return страница.evaluate(() => {
    const экран = document.getElementById('экран-рейтинга-игроков');
    const карточка = document.getElementById('рейтинг-моё-место');
    const вкладки = document.querySelector('.нижние-вкладки[data-вкладки="рейтинг"]');
    if (!экран || !карточка || !вкладки) {
      return { экранЕсть: Boolean(экран), карточкаЕсть: Boolean(карточка), вкладкиЕсть: Boolean(вкладки) };
    }
    const запас = parseFloat(getComputedStyle(экран).getPropertyValue('--рейтинг-моё-место-запас')) || 12;
    const rК = карточка.getBoundingClientRect();
    const rВ = вкладки.getBoundingClientRect();
    return {
      экранЕсть: true, карточкаЕсть: true, вкладкиЕсть: true, запас,
      карточкаTop: rК.top, карточкаBottom: rК.bottom, вкладкиTop: rВ.top,
      зазор: rВ.top - rК.bottom, className: карточка.className
    };
  });
}

