/* ---------------------------------------------------------------------
   Подготовка страницы: подделка Telegram + перехват дверей «/рейтинг»
   и «/style.css» + переход на экран рейтинга. Копия приёма из
   tests/рейтинг-на-пк.js.
   --------------------------------------------------------------------- */

async function открытьРейтинг(браузер, адрес, размер, ответДвери, путьСломанногоCSS) {
  const контекст = await браузер.newContext({ viewport: размер, hasTouch: размер.width < 700 });
  const страница = await контекст.newPage();

  await подготовитьПодделку(страница, { версия: '8.0' });

  /* img/рейтинг/катан.png и img/рейтинг/монополия.png на диске сейчас нет
     вовсе (отдельный, уже существующий пробел графики реестра игр — не
     моя задача и не style.css). Панель выбора игры просит их у любой
     ширины, стоит ей открыться (смоук «выбор игры» ниже), и без заглушки
     настоящий статический сервер честно отвечает 404 — это засоряло бы
     проверку «в консоли нет ошибок» чужой, не относящейся к делу бедой.
     Отдаём валидную 1×1 картинку вместо похода на диск. */
  const ЗАГЛУШКА_ЗНАЧКА = Buffer.from(
    'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=', 'base64');

  await перехватить(страница, /\/(?:рейтинг(?:\?|$)|style\.css(?:\?|$)|img\/рейтинг\/(?:катан|монополия)(?:@2x)?\.png)/,
    function (путь, запрос, адрес) {
      if (/\/рейтинг(?:\?|$)/.test(адрес)) {
        let игра = 'дурак';
        try {
          const тело = JSON.parse((запрос.postData && запрос.postData()) || '{}');
          if (тело && тело.игра) игра = тело.игра;
        } catch (о) { /* тела может не быть */ }
        путь.fulfill({ status: 200, contentType: 'application/json; charset=utf-8', body: JSON.stringify(ответДвери(игра)) });
        return;
      }
      if (путьСломанногоCSS && /\/style\.css(?:\?|$)/.test(адрес)) {
        путь.fulfill({ status: 200, contentType: 'text/css; charset=utf-8', body: fs.readFileSync(путьСломанногоCSS, 'utf8') });
        return;
      }
      if (/img\/рейтинг\/(?:катан|монополия)(?:@2x)?\.png/.test(адрес)) {
        путь.fulfill({ status: 200, contentType: 'image/png', body: ЗАГЛУШКА_ЗНАЧКА });
        return;
      }
      путь.continue();
    });

  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const т = м.text();
    const адресИсточника = (м.location() && м.location().url) || '';
    if (/telegram-web-app\.js|telegram\.org/.test(т) || /telegram-web-app\.js|telegram\.org/.test(адресИсточника)) return;
    /* Значки «Катан» и «Монополия» в панели выбора игры (img/рейтинг/
       катан.png, img/рейтинг/монополия.png) на диске сейчас нет вовсе —
       это отдельный, уже существующий пробел графики реестра игр,
       не имеет отношения к карточке «Моё место» и к style.css, который
       здесь правится. CSS у отсутствующего фона сам оставляет цветную
       подложку (см. «пунктПанелиИгр»), поломки экрана тут нет. */
    if (/img\/рейтинг\/(катан|монополия)(@2x)?\.png/.test(т) || /img\/рейтинг\/(катан|монополия)(@2x)?\.png/.test(адресИсточника)) return;
    красные.push('консоль: ' + т);
  });
  страница.on('requestfailed', (з) => {
    const адресЗапроса = з.url();
    if (/telegram-web-app\.js|telegram\.org/.test(адресЗапроса)) return;
    if (/img\/рейтинг\/(катан|монополия)(@2x)?\.png/.test(адресЗапроса)) return;
    красные.push('сеть: ' + адресЗапроса + ' — ' + (з.failure() && з.failure().errorText));
  });

  await страница.goto(адрес);
  await страница.waitForTimeout(400);
  await страница.click('#кнопка-вкладка-профиль');
  await страница.waitForSelector('#экран-рейтинга-игроков.экран--виден', { timeout: 10000 });
  await страница.waitForTimeout(500);

  return { контекст, страница, красные };
}

