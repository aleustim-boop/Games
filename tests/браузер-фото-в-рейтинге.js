/* ---------------------------------------------------------------------
   ОДИН обработчик на оба перехвата (/рейтинг и /фото/…) — раздельные
   route() ломают друг друга (см. шапку файла). В ломающем режиме
   ВСЕ «/фото/…» отвечают 404, включая честные ключи.
   --------------------------------------------------------------------- */
async function поставитьПерехват(страница, журнал) {
  /* Кроме /рейтинг и /фото/… здесь же гасим три фоновых скрипта, которых
     на момент написания сценария ещё не было: js/пульс.js, js/популярность.js
     и js/мой-аватар.js сами стучатся на АДРЕС_СЕРВЕРА_ВЫДУМАННЫЙ на путях
     /статистика, /пульс, /мой-аватар — без перехвата это ERR_UNSAFE_PORT
     в консоли (порт 9). Проверке они не нужны — отвечаем пустым «ок: false».
     ОДИН route на все пять дверей, см. шапку файла про раздельные route(). */
  await перехватить(страница, /\/(?:рейтинг(?:\?|$)|фото\/|статистика(?:\?|$)|пульс(?:\?|$)|мой-аватар(?:\?|$))/, function (путь, запрос, адрес) {
    if (/\/рейтинг(?:\?|$)/.test(адрес)) {
      путь.fulfill({ status: 200, contentType: 'application/json; charset=utf-8', body: JSON.stringify(ОТВЕТ_РЕЙТИНГА) });
      return;
    }
    if (/\/фото\//.test(адрес)) {
      журнал.push(адрес);
      const ключЗапрошенный = адрес.split('/фото/')[1];
      const этоЖивойКлюч = !СЛОМАТЬ && (ключЗапрошенный === КЛЮЧ_ЖИВОЙ_ПОДИУМ || ключЗапрошенный === КЛЮЧ_ЖИВОЙ_СПИСОК);
      if (этоЖивойКлюч) {
        путь.fulfill({ status: 200, contentType: 'image/png', body: КАРТИНКА_PNG });
      } else {
        путь.fulfill({ status: 404, contentType: 'text/plain; charset=utf-8', body: 'нет такой картинки' });
      }
      return;
    }
    // /статистика, /пульс, /мой-аватар — фоновые скрипты, проверке не нужны.
    путь.fulfill({ status: 200, contentType: 'application/json; charset=utf-8', body: JSON.stringify({ ок: false }) });
  });
}

async function запуститьПрогон() {
  if (!fs.existsSync(ПАПКА_СНИМКОВ)) fs.mkdirSync(ПАПКА_СНИМКОВ, { recursive: true });

  const браузер = await chromium.launch();
  const контекст = await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
  const страница = await контекст.newPage();

  const красные = [];
  const журналФото = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const текст = м.text();
    const откудаСырое = (м.location && м.location() && м.location().url) || '';
    // Браузер отдаёт адрес источника ЗАКОДИРОВАННЫМ («/фото/» уходит
    // как «/%D1%84%D0%BE%D1%82%D0%BE/») — раскодируем перед сверкой,
    // та же ловушка, что описана в tests/браузер-робот.js про «\bперехватить».
    let откуда = откудаСырое;
    try { откуда = decodeURIComponent(откудаСырое); } catch (о) { /* оставим как есть */ }
    const всёВместе = текст + ' ' + откуда;
    // Ожидаемый шум: внешний telegram-web-app.js (режет браузер-робот.js
    // нарочно) и ожидаемый 404 на «/фото/…» (именно его мы и просили —
    // браузер пишет «Failed to load resource: the server responded with
    // a status of 404» БЕЗ адреса в тексте, источник смотрим через
    // location().url, как в tests/рейтинг-на-пк.js).
    if (/telegram-web-app\.js|telegram\.org/.test(всёВместе)) return;
    if (/Failed to load resource/.test(текст) && /\/фото\//.test(откуда)) return;
    красные.push('консоль: ' + текст + (откуда ? ' (' + откуда + ')' : ''));
  });
  страница.on('requestfailed', (з) => {
    const адресЗапроса = з.url();
    if (/telegram-web-app\.js|telegram\.org/.test(адресЗапроса)) return;
    красные.push('сеть: ' + адресЗапроса + ' — ' + (з.failure() && з.failure().errorText));
  });

  await подготовитьПодделку(страница, { версия: '8.0' });
  await поставитьПерехват(страница, журналФото);

  await страница.goto(АДРЕС_СТРАНИЦЫ + '?сервер=' + encodeURIComponent(АДРЕС_СЕРВЕРА_ВЫДУМАННЫЙ),
    { waitUntil: 'domcontentloaded' });
  await страница.waitForFunction(() => Boolean(window.ЭкранРейтинга), { timeout: 8000 });

  await страница.evaluate(() => window.ЭкранРейтинга.открыть('дурак'));
  await страница.waitForFunction(() => {
    const э = document.getElementById('экран-рейтинга-игроков');
    return Boolean(э && э.classList.contains('экран--виден'));
  }, { timeout: 8000 });

  // Ждём, пока таблица нарисуется (хоть одно имя — подиум или строка).
  await страница.waitForFunction(() => {
    return document.querySelectorAll('#рейтинг-таблица .рейтинг-имя, #рейтинг-таблица .рейтинг-подиум-имя').length > 0;
  }, { timeout: 8000 });

  // Даём догрузиться настоящим картинкам (реальный HTTP через route,
  // реальные onload/onerror) — не таймер, а честное ожидание условия:
  // либо у живых мест появился класс, либо истёк разумный запас.
  await страница.waitForFunction(() => {
    const п1 = document.querySelector('.рейтинг-подиум-карточка[data-место="1"]');
    const с5 = document.querySelector('.рейтинг-строка[data-место="5"]');
    return Boolean(п1) && Boolean(с5) &&
      п1.classList.contains('рейтинг-строка--фото') && с5.classList.contains('рейтинг-строка--фото');
  }, { timeout: 5000 }).catch(() => { /* в обычном режиме дождёмся; в --сломать нарочно не дождёмся — так и должно быть */ });
  // Ещё немного времени на onerror у 404-го места — оно не меняет DOM,
  // ждать нечего кроме короткой паузы после того, как onload у живых уже случился.
  await страница.waitForTimeout(400);

  console.log('\n=== Проверки DOM ===');

  /* Видны ли буквы-инициалы взгляду человека — не по наличию/отсутствию
     класса на узле (класс мог остаться, а спрятать буквы должен был
     CSS), а по getComputedStyle самого узла букв: display:none,
     visibility:hidden, opacity:0 или нулевой размер — любой из них
     прячет буквы по-настоящему; во всех остальных случаях буквы видны
     и просвечивают сквозь/поверх фото — это баг вида, а не наш код,
     чинить его здесь не будем, только опишем в отчёте (см. задание). */
  async function буквыВидныВнутри(дескриптор) {
    return дескриптор.evaluate((э) => {
      const узел = э.querySelector('.рейтинг-аватар__инициалы');
      if (!узел) return { естьУзел: false, видны: false };
      const с = window.getComputedStyle(узел);
      const прямоуг = узел.getBoundingClientRect();
      const скрытСтилем = с.display === 'none' || с.visibility === 'hidden' || parseFloat(с.opacity) === 0;
      const скрытРазмером = прямоуг.width === 0 || прямоуг.height === 0;
      return {
        естьУзел: true,
        видны: !скрытСтилем && !скрытРазмером,
        display: с.display, visibility: с.visibility, opacity: с.opacity,
        ширина: прямоуг.width, высота: прямоуг.height
      };
    });
  }

  const карточка1 = await страница.$('.рейтинг-подиум-карточка[data-место="1"]');
  проверить('место 1 (подиум, честный ключ, фото есть): карточка нашлась', Boolean(карточка1));
  if (карточка1) {
    const класс1 = await карточка1.evaluate((э) => э.classList.contains('рейтинг-строка--фото'));
    // Ожидание ЖЁСТКОЕ, не подстроенное под флаг «--сломать»: класс обязан
    // быть — иначе ломающий режим (все «/фото/…» отвечают 404) никогда бы
    // не покраснел здесь, а тихо получал бы «ожидаемое отсутствие класса».
    проверить('место 1: класс «рейтинг-строка--фото» появился', класс1 === true, 'класс=' + класс1);
    const буквы1 = await буквыВидныВнутри(карточка1);
    проверить('место 1 (подиум): буквы-инициалы НЕ видны под настоящим фото',
      буквы1.естьУзел && буквы1.видны === false,
      'display=' + буквы1.display + ', visibility=' + буквы1.visibility + ', opacity=' + буквы1.opacity +
      ', размер=' + буквы1.ширина + 'x' + буквы1.высота);
  }

  const карточка2 = await страница.$('.рейтинг-подиум-карточка[data-место="2"]');
  проверить('место 2 (подиум, поля «фото» нет): карточка нашлась', Boolean(карточка2));
  if (карточка2) {
    const класс2 = await карточка2.evaluate((э) => э.classList.contains('рейтинг-строка--фото'));
    const буквы2 = await карточка2.$('.рейтинг-аватар__инициалы, .рейтинг-подиум-аватар .рейтинг-аватар__инициалы');
    проверить('место 2: класса «рейтинг-строка--фото» нет (поля не было)', класс2 === false, 'класс=' + класс2);
    проверить('место 2: буквы-инициалы на месте', Boolean(буквы2));
  }

  const карточка3 = await страница.$('.рейтинг-подиум-карточка[data-место="3"]');
  проверить('место 3 (подиум, честный ключ, /фото/ отвечает 404): карточка нашлась', Boolean(карточка3));
  if (карточка3) {
    const класс3 = await карточка3.evaluate((э) => э.classList.contains('рейтинг-строка--фото'));
    const буквы3 = await карточка3.$('.рейтинг-аватар__инициалы, .рейтинг-подиум-аватар .рейтинг-аватар__инициалы');
    проверить('место 3: класса «рейтинг-строка--фото» нет (сервер ответил 404)', класс3 === false, 'класс=' + класс3);
    проверить('место 3: буквы-инициалы остались вместо фото', Boolean(буквы3));
  }

  const строка4 = await страница.$('.рейтинг-строка[data-место="4"]');
  проверить('место 4 (список, поля «фото» нет): строка нашлась', Boolean(строка4));
  if (строка4) {
    const класс4 = await строка4.evaluate((э) => э.classList.contains('рейтинг-строка--фото'));
    const буквы4 = await строка4.$('.рейтинг-аватар__инициалы');
    проверить('место 4: класса «рейтинг-строка--фото» нет (поля не было)', класс4 === false, 'класс=' + класс4);
    проверить('место 4: буквы-инициалы на месте', Boolean(буквы4));
  }

  const строка5 = await страница.$('.рейтинг-строка[data-место="5"]');
  проверить('место 5 (список, честный ключ, фото есть): строка нашлась', Boolean(строка5));
  if (строка5) {
    const класс5 = await строка5.evaluate((э) => э.classList.contains('рейтинг-строка--фото'));
    проверить('место 5: класс «рейтинг-строка--фото» появился', класс5 === true, 'класс=' + класс5);
    const буквы5 = await буквыВидныВнутри(строка5);
    проверить('место 5 (список): буквы-инициалы НЕ видны под настоящим фото',
      буквы5.естьУзел && буквы5.видны === false,
      'display=' + буквы5.display + ', visibility=' + буквы5.visibility + ', opacity=' + буквы5.opacity +
      ', размер=' + буквы5.ширина + 'x' + буквы5.высота);
  }

  проверить('оба честных ключа (места 1 и 5) реально запрошены по /фото/…',
    журналФото.some((а) => а.indexOf(КЛЮЧ_ЖИВОЙ_ПОДИУМ) !== -1) && журналФото.some((а) => а.indexOf(КЛЮЧ_ЖИВОЙ_СПИСОК) !== -1),
    'запрошено: ' + журналФото.join(', '));

  проверить('консоль браузера чистая (кроме ожидаемого 404 на /фото/ и внешнего telegram-web-app.js)',
    красные.length === 0, красные.join(' | '));

  await страница.screenshot({ path: ПУТЬ_СНИМКА, fullPage: false });
  проверить('снимок записан: ' + ПУТЬ_СНИМКА, fs.existsSync(ПУТЬ_СНИМКА) && fs.statSync(ПУТЬ_СНИМКА).size > 0);

  await контекст.close();
  await браузер.close();
}

