/* ---------------------------------------------------------------------
   Собрать настоящий непрозрачный PNG (8-битный RGB, без палитры и без
   альфы) вручную — только встроенный «zlib» (deflateSync), без npm-
   пакетов. Формат: сигнатура + IHDR + один IDAT (все строки картинки,
   каждая с байтом фильтра 0) + IEND, у каждого чанка обычный CRC32.
   Ярко-синий сплошной квадрат виден человеку на снимке — прозрачная
   заглушка 1×1 (была здесь раньше) для смотрителя выглядит пустым
   кружком, хоть технически и грузится браузером.
   --------------------------------------------------------------------- */
const ТАБЛИЦА_CRC32 = (function () {
  const таблица = new Array(256);
  for (let n = 0; n < 256; n++) {
    let с = n;
    for (let k = 0; k < 8; k++) с = (с & 1) ? (0xEDB88320 ^ (с >>> 1)) : (с >>> 1);
    таблица[n] = с >>> 0;
  }
  return таблица;
})();
function crc32(буфер) {
  let crc = 0xFFFFFFFF;
  for (let i = 0; i < буфер.length; i++) crc = ТАБЛИЦА_CRC32[(crc ^ буфер[i]) & 0xFF] ^ (crc >>> 8);
  return (crc ^ 0xFFFFFFFF) >>> 0;
}
function pngЧанк(тип, данные) {
  const типБайты = Buffer.from(тип, 'ascii');
  const длина = Buffer.alloc(4); длина.writeUInt32BE(данные.length, 0);
  const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(Buffer.concat([типБайты, данные])), 0);
  return Buffer.concat([длина, типБайты, данные, crc]);
}
function собратьPNG(ширина, высота, цвет) {
  const [r, g, b] = цвет;
  const сигнатура = Buffer.from([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]);
  const ihdrДанные = Buffer.alloc(13);
  ihdrДанные.writeUInt32BE(ширина, 0);
  ihdrДанные.writeUInt32BE(высота, 4);
  ihdrДанные[8] = 8;  // глубина цвета — 8 бит на канал
  ihdrДанные[9] = 2;  // тип цвета 2 — RGB без альфы (непрозрачно)
  ihdrДанные[10] = 0; ihdrДанные[11] = 0; ihdrДанные[12] = 0;
  const байтНаСтроку = ширина * 3 + 1; // +1 — байт фильтра (0 — «без фильтра»)
  const сырые = Buffer.alloc(байтНаСтроку * высота);
  for (let y = 0; y < высота; y++) {
    const начало = y * байтНаСтроку;
    сырые[начало] = 0;
    for (let x = 0; x < ширина; x++) {
      const смещение = начало + 1 + x * 3;
      сырые[смещение] = r; сырые[смещение + 1] = g; сырые[смещение + 2] = b;
    }
  }
  const сжатые = zlib.deflateSync(сырые);
  return Buffer.concat([сигнатура, pngЧанк('IHDR', ihdrДанные), pngЧанк('IDAT', сжатые), pngЧанк('IEND', Buffer.alloc(0))]);
}
