  проверить('поздний ответ: пока сервер молчит, кнопка «Загружаем…»',
    Boolean(кнопкаВоВремя4) && кнопкаВоВремя4.textContent === 'Загружаем…');

  // Список переоткрывают до того, как старый дозапрос ответил.
  п4.окно.ЭкранРейтинга.открыть('дурак');
  await ждать();
  проверить('переоткрытие списка до ответа старого дозапроса — снова первая порция (10 строк)',
    строкиСписка(таблица4).length === 10);
  const кнопкаПосле4 = п4.документ.getElementById('кнопка-рейтинг-показать-ещё');
