  проверить('ошибок в консоли нет (сценарий 4)', п4.ошибкиКонсоли.length === 0);

  /* ---- Сценарий 5: ответ без поля «продолжение» — как до партии 9 ---- */
  const верхушкаСтарая = [];
  for (let м = 1; м <= 25; м++) верхушкаСтарая.push(игрок(м, 'Старый Игрок' + м, 30000 - м * 100));
