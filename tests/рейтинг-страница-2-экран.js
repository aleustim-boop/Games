function fetchОтвет(данные) {
  return function () {
    return Promise.resolve({ json: function () { return Promise.resolve(данные); } });
  };
}

/** Fetch, который решает ответ по разобранному телу запроса — рядом
    складывает все тела по порядку («запросы»), чтобы проверка могла
    свериться, что именно ушло на сервер (курсор, «сколько», игра). */
function сделатьFetch(обработать) {
  const запросы = [];
  const функция = function (адрес, настройки) {
    const тело = JSON.parse((настройки && настройки.body) || '{}');
    запросы.push(тело);
    return Promise.resolve(обработать(тело, запросы.length)).then(function (данные) {
      return { json: function () { return Promise.resolve(данные); } };
    });
  };
  функция.запросы = запросы;
  return функция;
}

function строкиСписка(таблица) {
  const все = Array.prototype.slice.call(таблица.querySelectorAll('.рейтинг-строка'));
  return все.filter(function (с) {
    return !с.classList.contains('рейтинг-строка--шапка') &&
           !с.classList.contains('рейтинг-строка--разрыв');
  });
}

