'use strict';

/* =====================================================================
   ВЕРСИИ НЕ РАЗЪЕХАЛИСЬ — проверка на разъезд номеров ?v= у общих файлов.

   Зачем это нужно. 22 сентября выяснилось, что js/рейтинг-экран.js был
   подключён на витрине как ?v=14, а на страницах нард, шахмат и шашек —
   как ?v=13. Больше суток три страницы из четырёх просили устаревший
   файл, и заметить это можно было только глазами. Правило проекта:
   изменил общий файл — подними ?v= у ВСЕХ страниц, которые его просят,
   одним коммитом. Разъезд номеров означает, что часть игроков сидит
   со старым кэшем и видит починенное сломанным.

   Что проверяем на каждой странице *.html из корня проекта (страницы
   ищем поиском по папке, а не списком имён — новая игра появится сама):
     3) один и тот же файл подключён на разных страницах с одним и тем
        же номером версии (иначе — краснеем и называем файл и все номера);
     4) у КАЖДОГО подключения есть ?v=N (иначе файл кэшируется навсегда);
     5) подключённый файл в самом деле лежит на диске (иначе — опечатка);
     6) подключений вообще что-то нашлось (ноль найденного — это провал,
        а не пропуск: значит, поиск сломан, а не что страницы идеальны).

   Как устроен ломающий запуск (--сломать). Настоящие index.html,
   нарды.html, шахматы.html, шашки.html не трогаем НИКОГДА. Вместо этого
   собираем их копии (плюс копии всех js-файлов и всех style*.css —
   иначе проверка «файл существует» ложно упадёт на всём подряд) во
   временной папке машины и портим уже ТОЛЬКО копии: у одного общего
   файла разводим версию на одной из страниц-копий, у другого подключения
   убираем ?v= целиком. Временную папку не удаляем — чистится сама.
   Дальше — две сверки, а не просто «дождались красного»:
     а) текст копии должен ОТЛИЧАТЬСЯ от текста настоящего файла проекта
        (иначе поломка не применилась, и это надо сказать прямо, красным);
     б) список покрасневших пунктов сверяется по ИМЕНАМ (какой файл,
        какая страница), а не только по счётчику — иначе переименование
        узла молча превратит проверку в украшение.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

/* ---------------------------------------------------------------------
   Разбор одной строки подключения («js/game.js?v=84» или «style.css»).
   Внешние адреса (https://telegram.org/...) и data:-ссылки — не наши
   файлы, версии у них не наши, поэтому такие подключения пропускаем
   и возвращаем null. --------------------------------------------------- */
function разобратьСсылку(страница, сыраяСсылка) {
  if (/^https?:\/\//i.test(сыраяСсылка) || /^data:/i.test(сыраяСсылка)) {
    return null;
  }
  const местоЗнакаВопроса = сыраяСсылка.indexOf('?');
  const файл = местоЗнакаВопроса === -1 ? сыраяСсылка : сыраяСсылка.slice(0, местоЗнакаВопроса);
  const запрос = местоЗнакаВопроса === -1 ? '' : сыраяСсылка.slice(местоЗнакаВопроса + 1);
  const совпадение = /^v=(\d+)$/.exec(запрос);
  return {
    страница: страница,
    файл: файл,
    сыраяСсылка: сыраяСсылка,
    версия: совпадение ? совпадение[1] : null,
  };
}

/* ---------------------------------------------------------------------
   Собрать все подключения js-скриптов и таблиц стилей со всех страниц
   *.html, найденных в папке. Страницы ищем readdirSync — не списком
   имён, вписанным сюда руками: появится пятая игра — увидим её сами. */
function собратьПодключения(корень) {
  const страницы = fs.readdirSync(корень).filter((имя) => /\.html$/i.test(имя)).sort();
  const подключения = [];

  for (const страница of страницы) {
    const текст = fs.readFileSync(path.join(корень, страница), 'utf8');

    const тегиСкриптов = текст.match(/<script\b[^>]*>/gi) || [];
    for (const тег of тегиСкриптов) {
      const совпадение = /\bsrc\s*=\s*(["'])(.*?)\1/i.exec(тег);
      if (!совпадение) continue; // инлайн-скрипт без src — проверять нечего
      const разобрано = разобратьСсылку(страница, совпадение[2]);
      if (разобрано) подключения.push(разобрано);
    }

    const тегиСтилей = текст.match(/<link\b[^>]*>/gi) || [];
    for (const тег of тегиСтилей) {
      if (!/rel\s*=\s*["']?stylesheet["']?/i.test(тег)) continue; // не таблица стилей (например, favicon)
      const совпадение = /\bhref\s*=\s*(["'])(.*?)\1/i.exec(тег);
      if (!совпадение) continue;
      const разобрано = разобратьСсылку(страница, совпадение[2]);
      if (разобрано) подключения.push(разобрано);
    }
  }

  return { страницы: страницы, подключения: подключения };
}

/* ---------------------------------------------------------------------
   Прогнать все правила по собранным подключениям и вернуть список
   провалов (каждый — с типом и именами, чтобы ломающий запуск мог
   сверить их по имени, а не только по числу). */
function проверить(корень) {
  const { страницы, подключения } = собратьПодключения(корень);
  const провалы = [];

  // Правило 6: ноль найденного — это провал, а не пропуск.
  if (подключения.length === 0) {
    провалы.push({
      тип: 'ничего-не-найдено',
      файл: null,
      страница: null,
      текст:
        `Поиск подключений не нашёл НИ ОДНОГО <script src="js/...?v=N"> и ` +
        `ни одного <link rel="stylesheet" ...?v=N"> ни на одной из ${страницы.length} ` +
        `найденных страниц (${страницы.join(', ') || 'страниц не найдено вовсе'}). ` +
        `Значит, либо поиск сломан, либо подключений в проекте не осталось — ` +
        `в обоих случаях ручаться за версии проверка не может.`,
    });
  }

  // Правило 3: один файл — разные номера версии на разных подключениях.
  const поФайлу = new Map();
  for (const п of подключения) {
    if (!поФайлу.has(п.файл)) поФайлу.set(п.файл, []);
    поФайлу.get(п.файл).push(п);
  }
  for (const [файл, список] of поФайлу) {
    const версии = Array.from(new Set(список.filter((п) => п.версия !== null).map((п) => п.версия)));
    if (версии.length > 1) {
      const подробности = список
        .map((п) => `${п.страница} → ${п.версия === null ? 'версии нет вовсе' : 'v=' + п.версия}`)
        .join('; ');
      провалы.push({
        тип: 'разъезд',
        файл: файл,
        страница: null,
        текст:
          `Файл «${файл}» подключён на разных страницах с РАЗНЫМИ номерами версии: ` +
          `${подробности}. Правило проекта — поднимать ?v= у ВСЕХ страниц разом одним ` +
          `коммитом; сейчас часть игроков получит устаревший файл из кэша.`,
      });
    }
  }

  // Правило 4: подключение вовсе без ?v=.
  for (const п of подключения) {
    if (п.версия === null) {
      провалы.push({
        тип: 'нет-версии',
        файл: п.файл,
        страница: п.страница,
        текст:
          `На странице «${п.страница}» файл «${п.файл}» подключён БЕЗ ?v=N ` +
          `(как в файле: «${п.сыраяСсылка}»). Такой файл браузер закэширует у ` +
          `игрока навсегда — правки в нём человек может не увидеть месяцами.`,
      });
    }
  }

  // Правило 5: подключённого файла нет на диске (опечатка в имени).
  for (const п of подключения) {
    const абсолютныйПуть = path.join(корень, ...п.файл.split('/'));
    if (!fs.existsSync(абсолютныйПуть)) {
      провалы.push({
        тип: 'файл-не-найден',
        файл: п.файл,
        страница: п.страница,
        текст:
          `На странице «${п.страница}» подключён файл «${п.файл}», которого нет ` +
          `на диске (искали здесь: ${абсолютныйПуть}). Похоже на опечатку в имени файла.`,
      });
    }
  }

  // «Итого проверок» — по числу найденных подключений (ровно то, что
  // читающий отчёт и назовёт «проверками»): каждое подключение проверено
  // и на версию, и на существование файла. Если подключений вообще нет,
  // единственная выполненная проверка — «нашлось ли хоть что-то».
  const итогоПроверок = подключения.length > 0 ? подключения.length : 1;

  return {
    страницы: страницы,
    подключения: подключения,
    провалы: провалы,
    итогоПроверок: итогоПроверок,
  };
}

/* Печать результата человеку — без технического образования тоже должно
   быть понятно, что именно сломалось и где чинить. */
function напечататьРезультат(результат, заголовок) {
  console.log(заголовок);
  console.log(`Страниц найдено: ${результат.страницы.length} (${результат.страницы.join(', ') || 'нет ни одной'})`);
  console.log(`Подключений найдено: ${результат.подключения.length}`);

  if (результат.провалы.length > 0) {
    console.log('');
    console.log('НАЙДЕНО:');
    результат.провалы.forEach((провал, номер) => {
      console.log(`${номер + 1}. [${провал.тип}] ${провал.текст}`);
    });
  }

  console.log('');
  console.log(`Итого проверок: ${результат.итогоПроверок}, провалов: ${результат.провалы.length}`);
}

/* ---------------------------------------------------------------------
   ЧИСТЫЙ ПРОГОН: проверяем настоящие страницы проекта. Настоящие файлы
   только читаем, никогда не пишем. */
function запуститьЧистыйПрогон() {
  const корень = path.join(__dirname, '..');
  const результат = проверить(корень);
  напечататьРезультат(результат, '=== Версии на настоящих страницах проекта ===');
  process.exit(результат.провалы.length > 0 ? 1 : 0);
}

/* ---------------------------------------------------------------------
   Собрать во временной папке рабочую копию проекта: страницы *.html
   (их и будем портить), все js-файлы и все style*.css — их портить не
   будем, но без них правило 5 («файл существует») ложно упадёт на всём
   подряд, и настоящая поломка потеряется в шуме. Настоящие файлы отсюда
   только читаются. Временная папка не удаляется — чистится сама. */
function собратьВременнуюКопию(корень) {
  const метка = 'версии-не-разъехались-сломать-' + Date.now() + '-' + Math.random().toString(36).slice(2, 8);
  const папка = path.join(os.tmpdir(), метка);
  fs.mkdirSync(path.join(папка, 'js'), { recursive: true });

  const страницы = fs.readdirSync(корень).filter((имя) => /\.html$/i.test(имя));
  for (const имя of страницы) {
    fs.copyFileSync(path.join(корень, имя), path.join(папка, имя));
  }

  const jsПапка = path.join(корень, 'js');
  for (const имя of fs.readdirSync(jsПапка)) {
    fs.copyFileSync(path.join(jsПапка, имя), path.join(папка, 'js', имя));
  }

  for (const имя of fs.readdirSync(корень)) {
    if (/^style.*\.css$/i.test(имя)) {
      fs.copyFileSync(path.join(корень, имя), path.join(папка, имя));
    }
  }

  return папка;
}

/* Заменить в файле-копии ровно первое вхождение точной строки и вернуть,
   применилась ли замена (текст правда изменился). Используем обычную
   строковую замену, а не regex: имена файлов — кириллические, а \b из
   регулярок кириллицу не знает, да и экранировать спецсимволы незачем. */
function заменитьВФайле(путь, было, стало) {
  const исходныйТекст = fs.readFileSync(путь, 'utf8');
  if (!исходныйТекст.includes(было)) {
    return { применилось: false, причина: `в файле не нашлась строка «${было}»` };
  }
  const новыйТекст = исходныйТекст.replace(было, стало);
  if (новыйТекст === исходныйТекст) {
    return { применилось: false, причина: 'замена не изменила текст файла' };
  }
  fs.writeFileSync(путь, новыйТекст, 'utf8');
  return { применилось: true };
}

/* ---------------------------------------------------------------------
   ЛОМАЮЩИЙ ЗАПУСК: портим КОПИИ и требуем, чтобы проверка покраснела
   ровно на двух подставленных поломках — по имени файла и страницы,
   а не только по количеству найденного. */
function запуститьЛомающийПрогон() {
  const корень = path.join(__dirname, '..');
  const папка = собратьВременнуюКопию(корень);

  // Собственная защита: писать разрешаем только внутри системной
  // временной папки, настоящий проект даже случайно не тронем.
  if (!папка.startsWith(os.tmpdir())) {
    console.log('ОСТАНОВЛЕНО: временная папка оказалась не во временном каталоге системы — портить отказываюсь.');
    process.exit(1);
    return;
  }

  const доПоломки = проверить(папка);
  if (доПоломки.подключения.length === 0) {
    console.log('Ломающий запуск не смог стартовать: во временной копии не нашлось ни одного подключения — портить нечего.');
    process.exit(1);
    return;
  }

  // Цель №1 (правило 3, «разъезд версий»): файл, встреченный на двух и
  // более страницах с ОДИНАКОВОЙ версией сейчас — понизим её на одной
  // странице и получим настоящий разъезд.
  const поФайлу = new Map();
  for (const п of доПоломки.подключения) {
    if (!поФайлу.has(п.файл)) поФайлу.set(п.файл, []);
    поФайлу.get(п.файл).push(п);
  }
  let цельРазъезд = null;
  for (const [файл, список] of поФайлу) {
    const страницыФайла = new Set(список.map((п) => п.страница));
    const версииФайла = new Set(список.filter((п) => п.версия !== null).map((п) => п.версия));
    if (страницыФайла.size >= 2 && версииФайла.size === 1 && список.some((п) => п.версия !== null)) {
      цельРазъезд = { файл: файл, запись: список.find((п) => п.версия !== null) };
      break;
    }
  }
  if (!цельРазъезд) {
    console.log('Ломающий запуск не смог найти общий файл на двух и более страницах с одинаковой версией — устраивать разъезд не на чем.');
    process.exit(1);
    return;
  }

  // Цель №2 (правило 4, «нет версии») — другое подключение с версией,
  // у другого файла, чтобы поломки не наступали друг другу на пятки.
  let цельБезВерсии = null;
  for (const п of доПоломки.подключения) {
    if (п.версия !== null && п.файл !== цельРазъезд.файл) {
      цельБезВерсии = п;
      break;
    }
  }
  if (!цельБезВерсии) {
    console.log('Ломающий запуск не смог найти второе подключение с версией у другого файла — портить нечего.');
    process.exit(1);
    return;
  }

  // --- Поломка №1: разводим версию файла на одной странице. ---
  const старыйНомер = parseInt(цельРазъезд.запись.версия, 10);
  const новыйНомер = старыйНомер > 0 ? старыйНомер - 1 : старыйНомер + 1;
  const результатПоломки1 = заменитьВФайле(
    path.join(папка, цельРазъезд.запись.страница),
    цельРазъезд.запись.сыраяСсылка,
    цельРазъезд.файл + '?v=' + новыйНомер
  );
  if (!результатПоломки1.применилось) {
    console.log(`ЛОМАЮЩИЙ ЗАПУСК НЕ ПРИМЕНИЛСЯ (поломка №1, разъезд версий): ${результатПоломки1.причина}.`);
    process.exit(1);
    return;
  }

  // --- Поломка №2: убираем ?v= у второго подключения целиком. ---
  const результатПоломки2 = заменитьВФайле(
    path.join(папка, цельБезВерсии.страница),
    цельБезВерсии.сыраяСсылка,
    цельБезВерсии.файл
  );
  if (!результатПоломки2.применилось) {
    console.log(`ЛОМАЮЩИЙ ЗАПУСК НЕ ПРИМЕНИЛСЯ (поломка №2, отсутствие версии): ${результатПоломки2.причина}.`);
    process.exit(1);
    return;
  }

  // Сверка «текст копии не равен тексту оригинала» — сравниваем именно
  // с настоящим файлом проекта (не тронутым), а не сами с собой.
  const настоящийТекст1 = fs.readFileSync(path.join(корень, цельРазъезд.запись.страница), 'utf8');
  const копияТекст1 = fs.readFileSync(path.join(папка, цельРазъезд.запись.страница), 'utf8');
  const настоящийТекст2 = fs.readFileSync(path.join(корень, цельБезВерсии.страница), 'utf8');
  const копияТекст2 = fs.readFileSync(path.join(папка, цельБезВерсии.страница), 'utf8');

  console.log('Сверка «текст копии не равен тексту оригинала»:');
  console.log(
    `  поломка №1 (${цельРазъезд.запись.страница}): ` +
      (копияТекст1 !== настоящийТекст1 ? 'текст копии отличается от настоящего файла — поломка применилась' : 'ПОЛОМКА НЕ ПРИМЕНИЛАСЬ — текст копии совпал с настоящим файлом')
  );
  console.log(
    `  поломка №2 (${цельБезВерсии.страница}): ` +
      (копияТекст2 !== настоящийТекст2 ? 'текст копии отличается от настоящего файла — поломка применилась' : 'ПОЛОМКА НЕ ПРИМЕНИЛАСЬ — текст копии совпал с настоящим файлом')
  );

  if (копияТекст1 === настоящийТекст1 || копияТекст2 === настоящийТекст2) {
    console.log('');
    console.log('ЛОМАЮЩИЙ ЗАПУСК ПРОВАЛЕН: копия не отличается от настоящего файла, поломка не применилась.');
    process.exit(1);
    return;
  }

  // Прогоняем ту же самую проверку по испорченной копии.
  const результат = проверить(папка);
  console.log('');
  напечататьРезультат(результат, '=== Ломающий запуск: та же проверка на испорченной КОПИИ во временной папке ===');

  // Самопроверка ПО ИМЕНАМ (какой файл, какая страница), а не по числу.
  const ожидания = [
    { тип: 'разъезд', файл: цельРазъезд.файл, страница: null },
    { тип: 'нет-версии', файл: цельБезВерсии.файл, страница: цельБезВерсии.страница },
  ];
  console.log('');
  console.log('Самопроверка ломающего запуска (сверка по именам, не по количеству):');
  let всёНашлось = true;
  for (const ожидание of ожидания) {
    const нашлось = результат.провалы.some(
      (провал) =>
        провал.тип === ожидание.тип &&
        провал.файл === ожидание.файл &&
        (ожидание.страница === null || провал.страница === ожидание.страница)
    );
    console.log(
      `  ожидали [${ожидание.тип}] файл «${ожидание.файл}»` +
        (ожидание.страница ? ` на странице «${ожидание.страница}»` : '') +
        ` — ${нашлось ? 'НАШЛОСЬ' : 'НЕ НАШЛОСЬ'}`
    );
    if (!нашлось) всёНашлось = false;
  }

  console.log('');
  console.log(`Временная копия для разбора (не удаляется, чистится сама системой): ${папка}`);

  if (!всёНашлось) {
    console.log('ЛОМАЮЩИЙ ЗАПУСК ВЫШЕЛ ЗЕЛЁНЫМ ТАМ, ГДЕ ДОЛЖЕН БЫЛ ПОКРАСНЕТЬ — это находка: проверка не ловит подставленную поломку.');
    process.exit(1);
    return;
  }

  console.log('Ломающий запуск исправен: обе подставленные поломки найдены проверкой именно по имени файла и страницы.');
  process.exit(0);
}

