/** В СТРАНИЦЕ: сон. Дверь: 'молчит' — не отвечает, 'отказ' — принято:false. */
function включитьСон(арг) {
  if (!window.ЛистЕщё || typeof window.ЛистЕщё.сон !== 'function') return 'нет ЛистЕщё.сон';
  window.__вызовыСна = 0;
  const двери = { проснуться: function () {
    window.__вызовыСна++;
    return арг.дверь === 'отказ' ? Promise.resolve({ принято: false }) : new Promise(function () {});
  } };
  window.ЛистЕщё.сон(арг.тексты, двери);
  return '';
}

/** В СТРАНИЦЕ: голосование с видимой плашкой (как его зовёт сеть.js). */
function включитьГолосование() {
  if (!window.ЛистЕщё || typeof window.ЛистЕщё.досрочно !== 'function') return 'нет ЛистЕщё.досрочно';
  window.ЛистЕщё.досрочно({
    строка: { видна: false, текст: 'Предложить закончить' },
    плашка: { видна: true, текст: 'Аня предлагает закончить партию', счёт: 'за 1 из 3', секунд: 30,
      отсчёт: function (n) { return n > 0 ? 'ещё ' + n + ' сек.' : ''; },
      кнопки: true, согласен: 'Согласен', дальше: 'Играть дальше', подпись: '' }
  }, { предложить: function () { return new Promise(function () {}); }, голос: function () { return new Promise(function () {}); } });
  return '';
}

/** В СТРАНИЦЕ: снять сон. */
function снятьСон() { window.ЛистЕщё.сон(null); return ''; }

/** В СТРАНИЦЕ: замер всей плашки. Не нашёл узел — { есть: false }. */
function замер(имена) {
  const W = document.documentElement.clientWidth, H = window.innerHeight;
  const корень = document.getElementById(имена.корень);
  const итог = { W: W, H: H, страницаШире: document.documentElement.scrollWidth > W + 1, корень: null };
  if (!корень) return итог;
  const прямоуг = function (р) { return { x: р.left, y: р.top, r: р.right, b: р.bottom, w: р.width, h: р.height }; };
  const видно = function (у) {
    if (!у) return false;
    const р = у.getBoundingClientRect(), с = getComputedStyle(у);
    return с.display !== 'none' && с.visibility !== 'hidden' && р.width > 0 && р.height > 0 && !у.closest('.скрыт');
  };
  const узел = function (класс) {
    const у = корень.querySelector('.' + класс);
    if (!у) return { есть: false };
    const р = у.getBoundingClientRect();
    const ц = document.elementFromPoint((р.left + р.right) / 2, (р.top + р.bottom) / 2);
    return Object.assign({ есть: true, виден: видно(у), текст: у.textContent.trim(), выключена: Boolean(у.disabled),
      обрезан: у.scrollWidth > у.clientWidth + 1,
      линияСнизу: parseFloat(getComputedStyle(у).borderBottomWidth) || 0,
      сама: Boolean(ц) && (у === ц || у.contains(ц)) }, прямоуг(р));
  };
  итог.корень = Object.assign({ виден: видно(корень), переполнен: корень.scrollWidth > корень.clientWidth + 1 || корень.scrollHeight > корень.clientHeight + 1,
    классСонИДругое: корень.classList.contains(имена.сонИДругое) }, прямоуг(корень.getBoundingClientRect()));
  итог.сонБлок = узел(имена.сонБлок);
  итог.сон = узел(имена.сон);
  итог.сбой = узел(имена.сбой);
  итог.кнопка = узел(имена.кнопка);
  итог.голосование = узел(имена.голосование);
  итог.кнопкиГолоса = узел(имена.кнопкиГолоса);
  return итог;
}

/* ---------- Прогон одного состояния ---------- */

const вЭкранеПоШирине = function (у, W) { return у.x >= -0.5 && у.r <= W + 0.5; };
const внутри = function (малый, большой) {
  return малый.x >= большой.x - 0.5 && малый.r <= большой.r + 0.5 && малый.y >= большой.y - 0.5 && малый.b <= большой.b + 0.5;
};

function m_узелСбояЕсть(м) { return Boolean(м.сбой && м.сбой.есть && м.сбой.текст === ''); }

/** Общие замеры плашки со сном. с — кнопка и строка сна видны; есть голосование — сравнение по высоте. */
function разобратьСон(м, п, слова, сГолосованием, сСбоем) {
  const к = м.кнопка, с = м.сон, р = м.корень;
  if (!сСбоем) проверить(m_узелСбояЕсть(м) && !м.сбой.виден, п + '[сбой-нет] без сбоя узел сбоя найден, но не виден и пуст («' + м.сбой.текст + '»)');
  if (!проверить(р && р.виден && с.есть && с.виден && к.есть && к.виден,
    п + '[сон-виден] плашка, строка сна и кнопка «Я здесь» найдены и видны (плашка ' + Boolean(р && р.виден) + ', строка ' + (с.есть && с.виден) + ', кнопка ' + (к.есть && к.виден) + ')')) return;
  проверить(с.текст.indexOf(слова.строка) === 0, п + '[сон-слова] слова сна — «' + слова.строка + '» (на экране «' + с.текст + '»)');
  проверить(вЭкранеПоШирине(с, м.W) && вЭкранеПоШирине(к, м.W), п + '[в-пределах-экрана] строка и кнопка целиком в экране по ширине (строка ' + Math.round(с.x) + '–' + Math.round(с.r) + ', кнопка ' + Math.round(к.x) + '–' + Math.round(к.r) + ', экран ' + м.W + ')');
  проверить(!м.страницаШире, п + '[в-пределах-экрана] у страницы нет горизонтальной прокрутки');
  проверить(к.y >= -0.5 && к.b <= м.H + 0.5, п + '[в-пределах-экрана] кнопка целиком в экране по высоте (' + Math.round(к.y) + '–' + Math.round(к.b) + ', экран ' + м.H + ')');
  проверить(к.h >= МИН_ВЫСОТА_КНОПКИ - 0.5, п + '[высота-кнопки] высота кнопки не меньше ' + МИН_ВЫСОТА_КНОПКИ + ' (вышло ' + Math.round(к.h) + ')');
  проверить(!с.обрезан && !к.обрезан, п + '[текст-цел] текст строки и кнопки не обрезан');
  проверить(внутри(с, р) && внутри(к, р), п + '[текст-в-плашке] строка и кнопка целиком внутри плашки');
  проверить(!р.переполнен, п + '[текст-в-плашке] содержимое плашки не вылезает из неё');
  проверить(с.b <= к.y + 0.5, п + '[текст-и-кнопка] строка сна не налезает на кнопку');
  проверить(к.сама, п + '[кнопка-достижима] в центре кнопки — она сама, её ничто не закрывает');
  проверить(р.h < м.H * 0.6 && р.b < м.H, п + '[не-весь-экран] плашка не закрывает весь экран (высота ' + Math.round(р.h) + ' из ' + м.H + ')');
  if (сГолосованием) {
    const г = м.голосование, кг = м.кнопкиГолоса;
    if (!проверить(г.есть && г.виден && кг.есть && кг.виден, п + '[голосование-видно] голосование в плашке найдено и видно')) return;
    проверить(м.сонБлок.b <= г.y + 0.5, п + '[сон-выше] сон стоит выше голосования и не перекрывается с ним (сон кончается на ' + Math.round(м.сонБлок.b) + ', голосование с ' + Math.round(г.y) + ')');
    проверить(р.классСонИДругое && м.сонБлок.линияСнизу >= 1, п + '[отделитель] между сном и голосованием есть линия (класс «' + ИМЕНА.сонИДругое + '»: ' + р.классСонИДругое + ', толщина ' + м.сонБлок.линияСнизу + ')');
    проверить(внутри(г, р) && внутри(кг, р) && р.b <= м.H + 0.5, п + '[текст-в-плашке] голосование целиком внутри плашки и экрана');
    проверить(вЭкранеПоШирине(г, м.W) && вЭкранеПоШирине(кг, м.W), п + '[в-пределах-экрана] голосование целиком в экране по ширине');
  } else {
    проверить(!м.голосование.виден, п + '[отделитель] голосования нет — и линии нет (класс «' + ИМЕНА.сонИДругое + '»: ' + р.классСонИДругое + ')');
  }
}

async function состояние(браузер, адрес, размер, имя, действия, разбор, подмены) {
  const п = размер.w + 'px ' + имя + ': ';
  console.log('\n--- ' + размер.w + '×' + размер.h + ' · ' + имя + ' ---');
  const ошибки = [];
  const контекст = await браузер.newContext({ viewport: { width: размер.w, height: размер.h }, reducedMotion: 'reduce' });
  try {
    const страница = await контекст.newPage();
    страница.on('pageerror', function (о) { ошибки.push('исключение: ' + о.message); });
    страница.on('console', function (с) { if (с.type() === 'error' && !/Failed to load resource/.test(с.text())) ошибки.push('консоль: ' + с.text()); });
    if (подмены && (подмены.стиль || подмены.лист)) {
      await страница.route('**/*', async function (запрос) {
        const путь = decodeURIComponent(new URL(запрос.request().url()).pathname);
        if (подмены.стиль && путь === '/' + ФАЙЛ_СТИЛЯ) return запрос.fulfill({ status: 200, contentType: 'text/css; charset=utf-8', body: fs.readFileSync(подмены.стиль) });
        if (подмены.лист && путь === '/' + ФАЙЛ_ЛИСТА) return запрос.fulfill({ status: 200, contentType: 'text/javascript; charset=utf-8', body: fs.readFileSync(подмены.лист) });
        return запрос.continue();
      });
    }
    await подготовитьПодделку(страница, {});
    await страница.goto(адрес + encodeURIComponent('домино.html') + '?сервер=' + encodeURIComponent('http://127.0.0.1:1'));
    await страница.waitForFunction(function () { return window.ЛистЕщё && typeof window.ЛистЕщё.сон === 'function'; }, null, { timeout: 8000 });
    await страница.waitForTimeout(400);
    const ош = await действия(страница);
    проверить(!ош, п + '[вызов] состояние вызвано на странице' + (ош ? ' (' + ош + ')' : ''));
    await страница.waitForTimeout(500);
    const м = await страница.evaluate(замер, ИМЕНА);
    if (проверить(Boolean(м.корень), п + '[сон-виден] корень плашки #' + ИМЕНА.корень + ' найден на странице')) await разбор(м, п, страница);
    const файл = path.join(ПАПКА, размер.w + '-' + имя.replace(/\s+/g, '-') + '.png');
    await страница.screenshot({ path: файл });
    console.log('  снимок: ' + файл);
    проверить(ошибки.length === 0, п + '[консоль] ошибок в консоли нет' + (ошибки.length ? ': ' + ошибки.join(' | ') : ''));
  } finally {
    await контекст.close();
  }
}

let ПАПКА = '';

async function прогнать(адрес, папка, подмены) {
  fs.mkdirSync(папка, { recursive: true });
  ПАПКА = папка;
  console.log('=== Плашка сна: снимки и замеры ===\nстраница: ' + адрес + 'домино.html\nснимки: ' + папка);
  for (const [ключ, значение] of Object.entries(ИМЕНА)) проверить(значение.length > 0, 'имя узла «' + ключ + '» прочитано из ' + ФАЙЛ_ЛИСТА + ' («' + значение + '»)');
  let браузер = null;
  try {
    браузер = await chromium.launch();
    const сон = function (дверь) { return function (с) { return с.evaluate(включитьСон, { тексты: ТЕКСТЫ_СНА, дверь: дверь }); }; };
    for (const размер of РАЗМЕРЫ) {
      await состояние(браузер, адрес, размер, 'только сон', сон('молчит'), function (м, п) { разобратьСон(м, п, ТЕКСТЫ_СНА, false);
        проверить(м.кнопка.текст === ТЕКСТЫ_СНА.кнопка && !м.кнопка.выключена, п + '[кнопка-видна] кнопка подписана «' + ТЕКСТЫ_СНА.кнопка + '» и живая («' + м.кнопка.текст + '»)'); }, подмены);

      await состояние(браузер, адрес, размер, 'сон в пути', async function (с) {
        const ош = await с.evaluate(включитьСон, { тексты: ТЕКСТЫ_СНА, дверь: 'молчит' });
        if (ош) return ош;
        await с.click('#' + ИМЕНА.корень + ' .' + ИМЕНА.кнопка, { timeout: 4000 });
        return '';
      }, async function (м, п, с) {
        разобратьСон(м, п, ТЕКСТЫ_СНА, false);
        проверить(м.кнопка.текст === ТЕКСТЫ_СНА.вПути && м.кнопка.выключена, п + '[в-пути] после нажатия кнопка висит со словом «' + ТЕКСТЫ_СНА.вПути + '» и выключена («' + м.кнопка.текст + '», выключена: ' + м.кнопка.выключена + ')');
        const вызовов = await с.evaluate(function () { return window.__вызовыСна; });
        проверить(вызовов === 1, п + '[нажатие] настоящее нажатие дошло до двери ровно один раз (вызовов ' + вызовов + ')');
      }, подмены);

      await состояние(браузер, адрес, размер, 'сон со сбоем', async function (с) {
        const ош = await с.evaluate(включитьСон, { тексты: ТЕКСТЫ_СНА, дверь: 'отказ' });
        if (ош) return ош;
        await с.click('#' + ИМЕНА.корень + ' .' + ИМЕНА.кнопка, { timeout: 4000 });
        await с.waitForFunction(function (а) {
          const к = document.querySelector('#' + а.корень + ' .' + а.кнопка), т = document.querySelector('#' + а.корень + ' .' + а.узелСбоя);
          return Boolean(к && т && !к.disabled && т.textContent.indexOf(а.сбой) !== -1);
        }, { корень: ИМЕНА.корень, кнопка: ИМЕНА.кнопка, узелСбоя: ИМЕНА.сбой, сбой: ТЕКСТЫ_СНА.сбой }, { timeout: 3000 }).catch(function () {});
        return '';
      }, function (м, п) {
        разобратьСон(м, п, ТЕКСТЫ_СНА, false, true);
        проверить(м.сбой.есть && м.сбой.виден && м.сбой.текст.indexOf(ТЕКСТЫ_СНА.сбой) !== -1, п + '[сбой] слова сбоя «' + ТЕКСТЫ_СНА.сбой + '» видны в своём узле («' + м.сбой.текст + '»)');
        проверить(м.сон.текст.indexOf(ТЕКСТЫ_СНА.сбой) === -1, п + '[сбой] строка сна слов сбоя не содержит («' + м.сон.текст + '»)');
        проверить(м.сбой.есть && м.сбой.y >= м.сон.b - 0.5 && м.сбой.b <= м.кнопка.y + 0.5,
          п + '[сбой] сбой стоит отдельной строкой между строкой сна и кнопкой (верх сбоя ' + Math.round(м.сбой.y) + ', низ строки сна ' + Math.round(м.сон.b) + ', низ сбоя ' + Math.round(м.сбой.b) + ', верх кнопки ' + Math.round(м.кнопка.y) + ')');
        проверить(м.сбой.есть && м.сбой.w >= м.сон.w - 1 && Math.abs(м.сбой.x - м.сон.x) <= 1,
          п + '[сбой] сбой — отдельный блок на всю ширину колонки, как строка сна, а не кусок строки (ширина сбоя ' + Math.round(м.сбой.w) + ', строки сна ' + Math.round(м.сон.w) + ')');
        console.log('  числа раскладки сбоя: верх сбоя ' + м.сбой.y.toFixed(1) + ', низ строки сна ' + м.сон.b.toFixed(1) + ', верх кнопки ' + м.кнопка.y.toFixed(1));
        проверить(м.кнопка.текст === ТЕКСТЫ_СНА.кнопка && !м.кнопка.выключена, п + '[сбой] кнопка вернулась («' + м.кнопка.текст + '», выключена: ' + м.кнопка.выключена + ')');
      }, подмены);

      await состояние(браузер, адрес, размер, 'сон и голосование', async function (с) {
        const ош = await с.evaluate(включитьСон, { тексты: ТЕКСТЫ_СНА, дверь: 'молчит' });
        return ош || await с.evaluate(включитьГолосование);
      }, function (м, п) { разобратьСон(м, п, ТЕКСТЫ_СНА, true); }, подмены);

      await состояние(браузер, адрес, размер, 'сон снят', async function (с) {
        const ош = await с.evaluate(включитьСон, { тексты: ТЕКСТЫ_СНА, дверь: 'молчит' });
        if (ош) return ош;
        const ош2 = await с.evaluate(включитьГолосование);
        return ош2 || await с.evaluate(снятьСон);
      }, function (м, п) {
        const р = м.корень;
        проверить(!м.сбой.виден, п + '[сбой-нет] после снятия сна узел сбоя не виден');
        проверить(!м.сон.виден && !м.кнопка.виден, п + '[сон-снят] строки сна и кнопки «Я здесь» на экране нет (строка видна: ' + м.сон.виден + ', кнопка видна: ' + м.кнопка.виден + ')');
        проверить(р.виден && м.голосование.виден, п + '[голосование-видно] плашка с голосованием осталась (плашка ' + р.виден + ', голосование ' + м.голосование.виден + ')');
        проверить(!р.классСонИДругое && м.сонБлок.линияСнизу === 0, п + '[отделитель] линии-отделителя нет (класс: ' + р.классСонИДругое + ', толщина ' + м.сонБлок.линияСнизу + ')');
        проверить(внутри(м.голосование, р) && р.b <= м.H + 0.5 && !м.страницаШире && вЭкранеПоШирине(р, м.W), п + '[в-пределах-экрана] плашка целиком в экране, без горизонтальной прокрутки');
        проверить(р.h < м.H * 0.6, п + '[не-весь-экран] плашка не закрывает весь экран (высота ' + Math.round(р.h) + ' из ' + м.H + ')');
      }, подмены);
    }
  } finally {
    if (браузер) await браузер.close();
  }
  console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
  process.exitCode = провалов > 0 ? 1 : 0;
}

