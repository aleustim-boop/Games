function ломатьОдной(порча, адрес, счёт) {
  console.log('=== Ломающий прогон: ' + порча.заголовок + ' — обязана покраснеть на ' + порча.метка + ' ===');
  счёт.всего++;
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'лист-сон-лом-'));
  try {
    const текст = fs.readFileSync(path.join(ПРОЕКТ, порча.файл), 'utf8');
    const вхождений = (текст.match(new RegExp(порча.найти.source, 'gm')) || []).length;
    if (вхождений !== 1) {
      console.log('ПРОВАЛ: не нашлось строки для порчи в ' + порча.файл + ' (нашлось ' + вхождений + ' раз, нужно ровно 1)');
      счёт.плохо++;
      return;
    }
    const копия = path.join(папка, path.basename(порча.файл));
    fs.writeFileSync(копия, текст.replace(порча.найти, порча.на), 'utf8');
    const доводы = [__filename, '--снимки', path.join(папка, 'снимки'), '--стенд', адрес, порча.файл === ФАЙЛ_СТИЛЯ ? '--стиль' : '--лист', копия];
    const прогон = spawnSync(process.execPath, доводы, { encoding: 'utf8', timeout: 500000 });
    const плохие = (прогон.stdout || '').split('\n').filter(function (с) { return с.includes('ПЛОХО'); });
    const наМетке = плохие.filter(function (с) { return с.includes(порча.метка); });
    console.log(наМетке.slice(0, 2).join('\n') + (прогон.stderr ? '\nstderr: ' + прогон.stderr.slice(0, 300) : ''));
    const ок = прогон.status === 1 && наМетке.length > 0;
    console.log(ок ? 'ПОКРАСНЕЛ на ' + порча.метка + ' (красных строк метки: ' + наМетке.length + ', всего красных: ' + плохие.length + ')'
      : 'ПРОВАЛ: не покраснел на ' + порча.метка + ' (код ' + прогон.status + ')');
    if (!ок) счёт.плохо++;
  } finally {
    fs.rmSync(папка, { recursive: true, force: true });
  }
}

function довод(имя) { const г = process.argv.indexOf(имя); return г !== -1 ? process.argv[г + 1] : null; }

const АДРЕС = довод('--стенд') || 'http://127.0.0.1:8137/';

if (process.argv.includes('--сломать')) {
  const счёт = { всего: 0, плохо: 0 };
  ПОРЧИ.forEach(function (порча) { ломатьОдной(порча, АДРЕС, счёт); });
  console.log('\nПоломок ' + счёт.всего + ', покраснело ' + (счёт.всего - счёт.плохо));
  process.exitCode = счёт.плохо ? 1 : 0;
} else {
  прогнать(АДРЕС, довод('--снимки') || path.join(ПРОЕКТ, 'tests', 'снимки', 'лист-сон'),
    { стиль: довод('--стиль'), лист: довод('--лист') }).catch(function (е) {
    console.error('ПРОВАЛ ЗАПУСКА: ' + (е && е.stack || е));
    process.exitCode = 1;
  });
}
