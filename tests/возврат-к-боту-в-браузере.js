const спать = (мс) => new Promise((готово) => setTimeout(готово, мс));

/** Поднимает tests/локальный-сервер.js дочерним процессом на нашем порту. */
function поднятьСервер() {
  const сервер = spawn('node', [
    path.join(__dirname, 'локальный-сервер.js'),
    String(ПОРТ)
  ], {
    env: Object.assign({}, process.env, { КОРЕНЬ_СЕРВЕРА: КОРЕНЬ_ПРОЕКТА }),
    stdio: 'pipe'
  });

  return new Promise((resolve, reject) => {
    let вывод = '';
    const таймаут = setTimeout(() => reject(new Error('Сервер не поднялся за 5 секунд')), 5000);
    сервер.stdout.on('data', (данные) => {
      вывод += данные.toString();
      console.log('  сервер: ' + данные.toString().trim());
      if (вывод.includes('запущен')) { clearTimeout(таймаут); resolve(сервер); }
    });
    сервер.stderr.on('data', (данные) => console.log('  ошибка сервера: ' + данные.toString().trim()));
    сервер.on('error', (е) => { clearTimeout(таймаут); reject(е); });
  });
}

/** Снимок состояния партии для сравнения «до» / «после» — прямо со страницы. */
function снятьСостояниеПартии() {
  /* Внутри страницы. Читаем «партия» через (0, eval) — как это делает
     готовый автоигрок (tests/автоигрок-в-браузере.js, функция
     «внутренности»): прямая лексическая ссылка не гарантирована для кода,
     вызванного из инжектированного контекста, indirect eval — гарантирован. */
  const глянуть = function (что) { return (0, eval)(что); };
  const п = глянуть('партия');
  if (!п) return null;
  const рука = (п.руки && п.руки.человек || []).map(function (к) { return к.масть + '-' + к.имя; }).sort();
  return {
    завершена: п.завершена,
    рука: рука,
    козырь: п.козырь,
    колодаДлина: п.колода ? п.колода.length : -1,
    столДлина: п.стол ? п.стол.length : -1,
    ходовЧеловека: (function () { try { return глянуть('ходовЧеловека'); } catch (e) { return -1; } })(),
    лимитСекундНаХод: п.лимитСекундНаХод || 0,
    остатокСекунд: (function () {
      try { return глянуть('остатокВремениНаХод')(п); } catch (e) { return null; }
    })()
  };
}

/** Ждём, пока автоигрок сделает хотя бы один настоящий ход человека. */
async function ждатьХотяБыОдинХодЧеловека(страница, максМс) {
  const шаг = 700;
  let прошло = 0;
  while (прошло < максМс) {
    await спать(шаг);
    прошло += шаг;
    const состояние = await страница.evaluate(снятьСостояниеПартии);
    if (!состояние) continue;
    if (состояние.завершена) return состояние;               // партия кончилась — дальше ждать нечего
    if (состояние.ходовЧеловека >= 1 && состояние.колодаДлина < 24) return состояние;
  }
  return await страница.evaluate(снятьСостояниеПартии);
}

