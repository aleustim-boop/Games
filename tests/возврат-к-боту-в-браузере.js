/** Генерирует имя файла с отметкой времени прогона: дата (ДДММ) и время (ЧЧММ). */
function получитьИмяСНимком() {
  const теперь = new Date();
  const д = String(теперь.getDate()).padStart(2, '0');
  const м = String(теперь.getMonth() + 1).padStart(2, '0');
  const ч = String(теперь.getHours()).padStart(2, '0');
  const мин = String(теперь.getMinutes()).padStart(2, '0');
  const отметка = д + м + '-' + ч + мин;
  return {
    png: path.join(ПАПКА_СНИМКОВ, 'возврат-к-боту-стол-' + отметка + '.png'),
    txt: path.join(ПАПКА_СНИМКОВ, 'возврат-к-боту-стол-' + отметка + '.txt')
  };
}

