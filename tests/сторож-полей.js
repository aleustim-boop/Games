/* =====================================================================
   СТОРОЖ ПОЛЕЙ — ОДИН НА ВСЕ СЕТЕВЫЕ ПРОГОНЫ.

   Смотрит, что сервер прислал игроку, и ищет чужое: карты не на своём
   месте, чужую руку, колоду, пропуск, номер в Telegram. Раньше он жил
   внутри tests/сетевой-автопрогон.js, и когда понадобился второй прогон
   (шашки по сети), сторожа пришлось бы завести второго. Два сторожа
   однажды разойдутся, и дыру будут искать неделю, — поэтому он один
   и лежит здесь.

   Пользоваться так:
       const { создатьСторожа } = require('./сторож-полей.js');
       const сторож = создатьСторожа(function (беда) { провалы.push(беда); });
       сторож.осмотреть(состояние, 'кто спрашивал');
       сторож.осмотретьКонверт(ответ, 'кто спрашивал');
       сторож.новыеПоля   // что незнакомое встретилось — показать человеку
   ===================================================================== */

/* =====================================================================
   ДВА СЛОЯ ВМЕСТО ОДНОГО СПИСКА — почему так.

   Раньше здесь был один белый список: всё, чего в нём нет, считалось
   утечкой. За месяц он отстал от сервера ПЯТЬ раз подряд («видСобытия»,
   «знакиВниманияЕсть», «знакВнимания», «подходов», «могуПодхватить»,
   теперь «броскиЕсть») — и каждый раз проверка краснела на честном
   новом поле. Сторож, который кричит на каждую честную мелочь, рано
   или поздно перестаёт быть сторожем: его правят не глядя, и в этот
   момент мимо него пройдёт настоящая утечка.

   Поэтому теперь поля делятся на три вида:

   1) ЗНАКОМЫЕ (список ниже) — про них уже разобрались, что они безопасны;
   2) ОПАСНЫЕ ПО ВИДУ (приметы ниже) — незнакомое поле, в имени которого
      слышится чужая рука, колода, отбой, пропуск или номер в Telegram.
      Это провал: даже если поле пустое, такому имени в ответе не место;
   3) ПРОСТО НОВЫЕ — незнакомые и на опасные не похожие. Это НЕ провал:
      стенд считает их, показывает в конце имя и образец значения, и
      просит человека решить. Партия при этом идёт дальше.

   Что от этого НЕ ослабло — самое главное. Карты ищутся по всему ответу
   вглубь, в любом поле, хоть в новом, хоть в старом: карта вне «мояРука»,
   «стол» и «козырнаяКарта» — всегда провал. Колода, отбой и карты
   соперника обязаны приходить числами. Эти проверки ниже, и они не
   зависят ни от каких списков имён.
   ===================================================================== */

/* Поля, про которые уже разобрались: они безопасны и бывают у ОБЕИХ игр.
   Всё, что бывает только у дурака или только у шашек, лежит ниже отдельно. */
const ЗНАКОМЫЕ_ПОЛЯ = new Set([
  'код', 'этап', 'версия', 'соперникПришёл', 'соперникНаСвязи', 'соперникУшёл',
  'событие', 'номерСобытия', 'сыграноПартий', 'яХочуЕщё', 'соперникХочетЕщё',
  'яХожу', 'завершена',
  /* «итог» — чем кончилась партия: победитель, ничья, причина словами и
     пометка «я выиграл». Бывает у обеих игр. Имён и карт в нём нет. */
  'итог',
  /* «мест» и «мойНомер» — сколько мест за столом и какое из них моё.
     Числа, ничего больше; страница по ним рисует рассадку. Встретились
     впервые в шашечной комнате, но поле общее для любой комнаты. */
  'мест',
  'мойНомер',
  /* «видСобытия» — одно слово из закрытого словаря сервера («взял», «отбился»
     и подобные, см. «видСобытия» в server/партия-по-сети.js). Карт и имён
     в нём нет, поэтому поле разрешено. Внесено сюда после того, как замер
     объявил его утечкой: список полей отстал от сервера, а не сервер начал
     болтать лишнее. */
  'видСобытия',
  /* Знаки внимания — смайлики и готовые фразы. Два поля, и оба безопасны.
     «знакиВниманияЕсть» — просто «да» или «нет»: умеет ли этот сервер
     знаки вообще (по нему страница решает, показывать ли кнопку).
     «знакВнимания» — номер знака из закрытого списка в js/game.js, имя
     приславшего и пометка «это я». Ни карт, ни свободного текста
     в них нет и быть не может: по сети едет только номер.
     Внесены сюда после того, как замер объявил их утечкой — и опять
     это список полей отстал от сервера, а не сервер разболтался.
     Так уже было с «видСобытия», строчкой выше. */
  'знакиВниманияЕсть',
  'знакВнимания',
  /* «подходов» — сколько подходов в партии уже сыграно, одно число. От него
     зависит потолок стола (в первом подходе пять карт, дальше шесть), и
     страница считает его правилами игры — своей копии числа у неё нет.
     Карт в нём нет, утечкой быть не может. Внесено после того, как замер
     дал 24 ложных «лишнее поле»: список отстал от сервера — в третий раз.
     (Само поле бывает только у дурака и лежит в его списке ниже.)
     «могуПодхватить» — оттуда же: «да» или «нет», есть ли у меня карта,
     которой можно бросить заходной вне очереди. Считается по МОЕЙ руке
     и карт не раскрывает; без него замер давал 3997 ложных «лишнее поле» —
     список отстал от сервера в четвёртый раз. */
  /* «броскиЕсть» — «да» или «нет»: умеет ли этот сервер броски предметов
     (по нему страница решает, показывать ли кнопку). Ни карт, ни имён,
     ни свободного текста. Пятый случай отставания списка от сервера —
     после него список и переделан в два слоя, см. заметку выше. */
  'броскиЕсть',
  /* «игра» — одно слово из реестра сервера: «дурак» или «шашки». По нему
     страница узнаёт, что рисовать: стол с картами или доску. Слово закрытое,
     из реестра, а не из запроса игрока. Шестой случай нового поля — и первый,
     на котором сторож уже не покраснел, а честно показал: «новое поле
     «игра» = "дурак", посмотрите глазами». Ради этого его и переделывали. */
  'игра',
  /* «застолом» — список мест: номер, имя, «это я», «это бот», сколько карт
     у каждого. Имена за столом игроки и так видят, карт — числом. Само поле
     тут, а его начинку сторож просматривает вглубь (см. «поИменам»). */
  'застолом'
]);

/* ---------------------------------------------------------------------
   Поля, которые бывают только у одной игры

   Сервер теперь держит две игры, и наборы полей у них разные: у дурака
   карты и колода, у шашек доска и цвет. Мешать их в одну кучу нельзя —
   тогда «доска» стала бы законной в ответе про дурака, а «козырь»
   в ответе про шашки, и сторож перестал бы замечать чужое.
   --------------------------------------------------------------------- */

/** Поля, которые бывают только у дурака. */
const ПОЛЯ_ДУРАКА = new Set([
  'козырь', 'козырнаяКарта', 'вКолоде', 'вОтбое', 'мояРука', 'картУСоперника',
  'стол', 'фаза', 'яАтакую', 'берут', 'подходов', 'могуПодхватить', 'видСобытия'
]);

/** Поля, которые бывают только у шашек по сети.
    Списка для них не было вовсе — завёл, сняв поля с живого сервера.
    «доска» тут не утечка: в шашках оба игрока видят всю доску целиком,
    прятать нечего. Тем важнее, что для дурака этого слова в списке нет. */
const ПОЛЯ_ШАШЕК = new Set([
  'доска',        // восемь строк по восемь знаков: где чьи шашки и дамки
  'чейХод',       // «белые» или «чёрные»
  'мойЦвет',      // каким цветом играю я
  'естьБой',      // есть ли обязательный бой
  'яХозяин',      // я ли завёл комнату
  'можноНачать',  // можно ли начинать партию
  /* «последнийХод» — как прошёл прошлый ход: откуда, куда, полный путь
     цепочки боя и список побитых полей. Полный путь сервер шлёт нарочно:
     без него чужой бой на экране выглядел бы телепортацией. Имени того,
     кто ходил, тут нет — только пометка «мой». */
  'последнийХод'
]);

/** Знакомые поля для той игры, что идёт в этой комнате. */
function знакомыеДляИгры(игра) {
  const свои = игра === 'шашки' ? ПОЛЯ_ШАШЕК : ПОЛЯ_ДУРАКА;
  const всё = new Set(ЗНАКОМЫЕ_ПОЛЯ);
  свои.forEach(function (поле) { всё.add(поле); });
  return всё;
}

/* Незнакомое поле, в имени которого слышится чужая рука, колода, отбой,
   пропуск или номер игрока в Telegram. Такому в ответе игроку не место —
   это провал, даже если поле сейчас пустое.
   Знакомые поля сюда не попадают вовсе: их проверяют раньше. */
const ОПАСНЫЕ_ПРИМЕТЫ = [
  { примета: /рук/i, чем: 'похоже на чью-то руку' },
  { примета: /колод/i, чем: 'похоже на колоду' },
  { примета: /отбо/i, чем: 'похоже на отбой' },
  { примета: /карт/i, чем: 'похоже на карты' },
  { примета: /масть|достоинств/i, чем: 'похоже на части карты' },
  { примета: /пропуск|токен|секрет|пароль|ключ/i, чем: 'похоже на пропуск игрока' },
  { примета: /telegram|tg[_-]|chat|user[_-]?id|номерИгрока/i, чем: 'похоже на номер игрока в Telegram' }
];

/* Новые поля, на опасные не похожие: копим и показываем в конце.
   Ключ — имя поля, значение — образец, чтобы человеку было что решать. */
const новыеПоля = new Map();

/* Кому докладывать о каждой проверке. Ставится в «создатьСторожа». */
let доложить = function () {};
let осмотреноОтветов = 0;

/** Одна проверка: докладываем наружу и «да», и «нет» — счёт ведёт прогон. */
function проверить(условие, что) { доложить(Boolean(условие), что); }

/* ---------------------------------------------------------------------
   Две двери мимо игрового стола: список знакомых и статистика

   Их не смотрел никто, а отдают они самое чувствительное: чужие имена
   и числа владельца. Правило простое: номеров Telegram там быть не должно
   вовсе — ни в одном поле, ни в глубине.
   --------------------------------------------------------------------- */

/** Что имеет право лежать в строке списка знакомых. */
const ПОЛЯ_ЗНАКОМОГО = new Set([
  'имя',           // как человек подписался — его и так видно за столом
  'сейчасИграет',  // да/нет: сидит ли он сейчас за каким-нибудь столом
  'игра'           // во что играли в последний раз: слово из реестра
]);

/** Похоже ли значение на номер игрока в Telegram (длинное число). */
function похожеНаНомерTelegram(значение) {
  if (typeof значение === 'number') return Number.isInteger(значение) && Math.abs(значение) >= 10000;
  return typeof значение === 'string' && /^\d{5,}$/.test(значение.trim());
}

/**
 * Осмотреть ответ двери /знакомые.
 * Ищем ровно две вещи: лишние поля в строке и номера Telegram где угодно.
 */
function осмотретьЗнакомых(данные, откуда) {
  осмотреноОтветов++;
  const список = (данные && данные.знакомые) || [];
  проверить(Array.isArray(список), откуда + ': список знакомых пришёл не списком');
  if (!Array.isArray(список)) return;

  список.forEach(function (строка, номер) {
    Object.keys(строка || {}).forEach(function (поле) {
      проверить(ПОЛЯ_ЗНАКОМОГО.has(поле),
        откуда + ': в строке знакомого №' + (номер + 1) + ' лишнее поле «' + поле +
        '» = ' + образец(строка[поле]));
      проверить(!похожеНаНомерTelegram(строка[поле]),
        откуда + ': в строке знакомого «' + поле + '» похоже на номер Telegram — ' + образец(строка[поле]));
    });
  });
  искатьНомераTelegram(данные, откуда + ' (знакомые)');
}

/**
 * Осмотреть ответ двери /статистика.
 * Здесь всё обязано быть числами: имена людей — не наше дело, а номеров
 * Telegram не должно быть даже в ключах. Имена счётчиков бывают
 * с двоеточием («партийНачато:шашки») — это разбивка по играм, и делить
 * строку по двоеточию нельзя: имя счётчика берём целиком.
 */
function осмотретьСтатистику(данные, откуда) {
  осмотреноОтветов++;
  const сводки = ['сегодня', 'дней7', 'дней30'];
  сводки.forEach(function (имяСводки) {
    const сводка = данные && данные[имяСводки];
    if (!сводка) return;
    Object.keys(сводка).forEach(function (счётчик) {
      проверить(typeof сводка[счётчик] === 'number',
        откуда + ': счётчик «' + счётчик + '» пришёл не числом — ' + образец(сводка[счётчик]));
      проверить(!похожеНаНомерTelegram(счётчик),
        откуда + ': имя счётчика похоже на номер Telegram — «' + счётчик + '»');
    });
  });
  искатьНомераTelegram(данные, откуда + ' (статистика)');
}

/** Пройти ответ вглубь и не найти ни одного номера Telegram. */
function искатьНомераTelegram(узел, путь) {
  if (!узел || typeof узел !== 'object') return;
  Object.keys(узел).forEach(function (поле) {
    const значение = узел[поле];
    /* Числа-счётчики бывают большими законно (партий сыграно), поэтому
       на номер проверяем только строки и поля, чьё имя намекает на человека. */
    if (typeof значение === 'string' && /^\d{7,}$/.test(значение.trim())) {
      проверить(false, путь + ': в поле «' + поле + '» лежит длинное число, похожее на номер Telegram');
    }
    if (/telegram|tg[_-]|user[_-]?id|chat/i.test(поле)) {
      проверить(false, путь + ': поле «' + поле + '» названо так, будто в нём номер игрока');
    }
    искатьНомераTelegram(значение, путь + '.' + поле);
  });
}
/* ---------------------------------------------------------------------
   Сыщик: ищет чужие карты в том, что пришло игроку
   --------------------------------------------------------------------- */

/** Похоже ли это на карту. */
function этоКарта(что) {
  return что && typeof что === 'object' && что.масть !== undefined && что.имя !== undefined;
}

/** Короткий образец значения — чтобы в отчёте было видно, что за поле пришло. */
function образец(значение) {
  let текст;
  try { текст = JSON.stringify(значение); } catch (сбой) { текст = String(значение); }
  if (текст === undefined) текст = String(значение);
  return текст.length > 60 ? текст.slice(0, 60) + '…' : текст;
}

/**
 * Осмотреть состояние: нет ли в нём полей, которых там быть не должно,
 * и не лежит ли карта там, где полагается лежать только числу.
 */
function осмотреть(состояние, откуда) {
  if (!состояние) return;
  осмотреноОтветов++;

  // Какой игрой заняты — по этому выбираем, какие поля считать знакомыми
  const знакомые = знакомыеДляИгры(состояние.игра);

  Object.keys(состояние).forEach(function (поле) {
    if (знакомые.has(поле)) return;                      // про это поле уже разобрались
    const опасное = ОПАСНЫЕ_ПРИМЕТЫ.find(function (п) { return п.примета.test(поле); });
    if (опасное) {
      проверить(false, откуда + ': в ответе поле «' + поле + '» — ' + опасное.чем +
        ', такому имени тут не место (значение: ' + образец(состояние[поле]) + ')');
      return;
    }
    // Просто новое поле: не валим прогон, но запоминаем и покажем в конце
    if (!новыеПоля.has(поле)) новыеПоля.set(поле, (состояние.игра || 'дурак') + ': ' + образец(состояние[поле]));
  });

  /* Имена ВНУТРИ ответа, а не только сверху. Раньше сторож смотрел только
     верхний ярус, и чужая рука, спрятанная на ярус глубже (скажем,
     «застолом[0].картыСоперника»), прошла бы мимо. Числа и «да/нет»
     пропускаем: в них не спрячешь ни карту, ни пропуск, а поле «карт: 6»
     в списке за столом — законное. */
  (function поИменам(узел, путь) {
    if (!узел || typeof узел !== 'object') return;
    /* Внутрь самой карты не лезем: «масть», «имя» и «вес» — это её законные
       части, а не подозрительные поля. Что карта лежит в дозволенном месте
       и что лишних частей у неё нет — проверяет обход ниже. */
    if (этоКарта(узел)) return;
    Object.keys(узел).forEach(function (поле) {
      const значение = узел[поле];
      const простое = typeof значение === 'number' || typeof значение === 'boolean' || значение === null;
      if (путь && !простое) {
        const опасное = ОПАСНЫЕ_ПРИМЕТЫ.find(function (п) { return п.примета.test(поле); });
        if (опасное && !знакомые.has(поле)) {
          проверить(false, откуда + ': внутри ответа поле «' + путь + '.' + поле + '» — ' + опасное.чем +
            ' (значение: ' + образец(значение) + ')');
        }
      }
      поИменам(значение, путь ? путь + '.' + поле : поле);
    });
  })(состояние, '');

  /* Дальше — счёт карт, и он только про дурака: в шашках нет ни колоды,
     ни отбоя, ни чужой руки, а доску оба игрока и так видят целиком.
     Раньше эти три проверки шли всем подряд, и первая же шашечная комната
     дала семь ложных провалов. */
  if (состояние.игра !== 'шашки') {
    проверить(typeof состояние.картУСоперника === 'number',
      откуда + ': карты соперника пришли не числом');
    // Пока друг не пришёл, карт нет вовсе — счётчиков колоды и отбоя в ответе
    // просто не бывает, и это правильно. Спрашиваем их только за начатой партией.
    if (состояние.этап !== 'ожидание') {
      проверить(typeof состояние.вКолоде === 'number', откуда + ': колода пришла не числом');
      проверить(typeof состояние.вОтбое === 'number', откуда + ': отбой пришёл не числом');
      проверить(!(состояние.вКолоде === 0 && состояние.козырнаяКарта),
        откуда + ': колода пуста, а козырную карту всё ещё показывают');
    }
  } else {
    /* А это — только про шашки: доска обязана быть восемью строками,
       и ни одной карты в шашечном ответе быть не может вовсе. */
    проверить(!состояние.доска || (Array.isArray(состояние.доска) && состояние.доска.length === 8),
      откуда + ': доска пришла не восемью строками');
    проверить(состояние.мояРука === undefined && состояние.вКолоде === undefined,
      откуда + ': в шашечном ответе оказались карточные поля');
  }

  // Ищем карты во всех углах ответа, кроме трёх законных мест
  (function обход(узел, путь) {
    if (!узел || typeof узел !== 'object') return;
    if (этоКарта(узел)) {
      проверить(/^(мояРука|стол|козырнаяКарта)/.test(путь),
        откуда + ': карта лежит там, где карт быть не должно — ' + путь);
      проверить(Object.keys(узел).length === 3,
        откуда + ': у карты появились лишние поля — ' + Object.keys(узел).join(','));
      return;
    }
    Object.keys(узел).forEach(function (к) {
      обход(узел[к], путь ? путь + '.' + к : к);
    });
  })(состояние, '');
}

/* Что сервер имеет право положить в САМ ОТВЕТ, рядом с «состояние». */
const ПОЛЯ_КОНВЕРТА = new Set([
  'состояние',   // сам вид стола, его осматривает «осмотреть» отдельно
  'код',         // код комнаты — его игрок и так знает, он его и вводил
  'пропуск',     // МОЙ пропуск, выданный мне же при входе; чужого тут быть не может
  'принято',     // «да/нет» на мой ход
  'причина',     // почему ход не принят, словами
  'ошибка',      // отказ сервера словами
  'новость',     // длинный опрос: есть ли новости
  'ждать',       // длинный опрос: сколько ждать до следующего вопроса
  'изменилось'   // длинный опрос: «да» — за столом что-то поменялось
]);

/**
 * Осмотреть САМ ОТВЕТ, а не только «состояние» внутри него.
 *
 * Зачем отдельно. Сторож всю жизнь смотрел только в «состояние» — и всё,
 * что сервер положил бы рядом с ним, проходило мимо совсем. Дыра тихая:
 * положи сервер в ответ чужой пропуск или вторую руку одним ярусом выше,
 * и ни одна проверка бы не пикнула. Теперь смотрим оба яруса.
 */
function осмотретьКонверт(данные, откуда) {
  if (!данные || typeof данные !== 'object') return;

  Object.keys(данные).forEach(function (поле) {
    if (ПОЛЯ_КОНВЕРТА.has(поле)) return;
    const опасное = ОПАСНЫЕ_ПРИМЕТЫ.find(function (п) { return п.примета.test(поле); });
    if (опасное) {
      проверить(false, откуда + ': рядом с состоянием лежит поле «' + поле + '» — ' + опасное.чем +
        ' (значение: ' + образец(данные[поле]) + ')');
      return;
    }
    if (!новыеПоля.has('(в конверте) ' + поле)) новыеПоля.set('(в конверте) ' + поле, образец(данные[поле]));
  });

  // Карт рядом с состоянием быть не может вовсе — ни одной и нигде
  (function обход(узел, путь) {
    if (!узел || typeof узел !== 'object') return;
    if (этоКарта(узел)) {
      проверить(false, откуда + ': карта лежит в самом ответе, вне состояния — ' + путь);
      return;
    }
    Object.keys(узел).forEach(function (к) {
      if (!путь && к === 'состояние') return;      // его смотрит «осмотреть»
      обход(узел[к], путь ? путь + '.' + к : к);
    });
  })(данные, '');
}

/**
 * Завести сторожа. «доложитьСнаружи(условие, что)» зовут на каждую проверку:
 * прогон сам решает, считать ли её и куда писать провал.
 */
function создатьСторожа(доложитьСнаружи) {
  доложить = доложитьСнаружи;
  осмотреноОтветов = 0;
  новыеПоля.clear();
  return {
    осмотреть: осмотреть,
    осмотретьКонверт: осмотретьКонверт,
    осмотретьЗнакомых: осмотретьЗнакомых,
    осмотретьСтатистику: осмотретьСтатистику,
    новыеПоля: новыеПоля,
    сколькоОсмотрено: function () { return осмотреноОтветов; }
  };
}

module.exports = { создатьСторожа: создатьСторожа, ЗНАКОМЫЕ_ПОЛЯ: ЗНАКОМЫЕ_ПОЛЯ, ПОЛЯ_ДУРАКА: ПОЛЯ_ДУРАКА, ПОЛЯ_ШАШЕК: ПОЛЯ_ШАШЕК };
