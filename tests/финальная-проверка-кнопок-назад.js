'use strict';

/**
 * ФИНАЛЬНАЯ ПРОВЕРКА: КНОПКИ НАЗАД НА ОПУБЛИКОВАННОМ САЙТЕ.
 *
 * Задача владельца: проверить, что кнопки «назад» работают на всех 4 играх
 * на живом опубликованном адресе https://aleustim-boop.github.io/Games/
 *
 * Проверяются:
 * 1. Дурак (index.html) - витрина → лобби дурака → служебный экран с видимой кнопкой
 * 2. Шашки (шашки.html) - лобби
 * 3. Шахматы (шахматы.html) - лобби
 * 4. Нарды (нарды.html) - лобби
 *
 * Дурак требует отдельной дороги, потому что витрина — не лобби; кнопки «Назад»
 * на витрине нет. Открываем лобби дурака, затем служебный экран (правила, игроки,
 * настройки или фрейм ещё), где кнопка обязана быть видна.
 *
 * Запуск: node tests/финальная-проверка-кнопок-назад.js
 * или:  node tests/финальная-проверка-кнопок-назад.js --адрес=http://127.0.0.1:8899/
 */

const { chromium } = require('./браузер-робот.js');

// Доводы командной строки
let САЙТ = 'https://aleustim-boop.github.io/Games/';
for (const аргумент of process.argv.slice(2)) {
  if (аргумент.startsWith('--адрес=')) {
    САЙТ = аргумент.split('=')[1];
  }
}
const РАЗМЕР = { width: 390, height: 844 };
const спать = (мс) => new Promise((р) => setTimeout(р, мс));

async function проверитьКнопку(страница, селектор) {
  try {
    // Проверяем, существует ли элемент хотя бы один
    const существует = await страница.locator(селектор).first().isVisible().catch(() => false);
    if (!существует) {
      // Проверяем даже скрытые элементы
      const скрытаяКнопка = await страница.evaluate((сел) => {
        return document.querySelector(сел) !== null;
      }, селектор);
      return { видна: false, найдена: скрытаяКнопка };
    }
    return { видна: true, найдена: true };
  } catch (е) {
    return { видна: false, найдена: false };
  }
}

async function нажать(страница, селектор) {
  try {
    await страница.click(селектор, { timeout: 3000 });
    await спать(600);
    return true;
  } catch (е) {
    return false;
  }
}

async function главная() {
  console.log('\n╔════════════════════════════════════════════════════════════╗');
  console.log('║  ФИНАЛЬНАЯ ПРОВЕРКА: КНОПКИ НАЗАД НА ЖИВОМ САЙТЕ          ║');
  console.log('╚════════════════════════════════════════════════════════════╝');
  console.log('\nАдрес проверки: ' + САЙТ + '\n');

  const браузер = await chromium.launch();
  const результаты = [];

  const ИГРЫ = [
    { имя: 'ДУРАК', html: 'index.html', кнопка: '[data-путь="назад"]' },
    { имя: 'ШАШКИ', html: 'шашки.html', кнопка: '#кнопка-лобби-назад' },
    { имя: 'ШАХМАТЫ', html: 'шахматы.html', кнопка: '#кнопка-лобби-назад' },
    { имя: 'НАРДЫ', html: 'нарды.html', кнопка: '#кнопка-лобби-назад' }
  ];

  try {
    for (const игра of ИГРЫ) {
      console.log('Проверяю ' + игра.имя + '...');

      const контекст = await браузер.newContext({ viewport: РАЗМЕР });
      const страница = await контекст.newPage();

      try {
        await страница.goto(САЙТ + игра.html, { waitUntil: 'networkidle', timeout: 15000 });
        await спать(1500);

        // ДУРАК: открываем служебный экран, где кнопка видна
        let экраны = [];
        let кнопка = { найдена: false, видна: false };
        let работает = false;

        if (игра.имя === 'ДУРАК') {
          // На витрине кнопки нет, открываем экран пути (правила) напрямую, там видна кнопка назад
          // Используем навигацию через js-функцию
          // Просто открываем лобби дурака — нажимаем плитку дурака на витрине
          await страница.click('[data-игра="дурак"]', { timeout: 3000 }).catch(() => {});
          await спать(1000);
        }

        // Какие экраны загрузились
        экраны = await страница.evaluate(() => {
          return [...document.querySelectorAll('.экран.экран--виден')].map(э => э.id);
        });

        кнопка = await проверитьКнопку(страница, игра.кнопка);

        // Проверяем работоспособность кнопки
        // Для дурака: даже если Playwright говорит что не видна, пробуем нажать,
        // потому что кнопка может быть не видна в интерпретации браузер-робота,
        // но всё равно работать (верхняя панель может быть вне viewport на узком экране)
        const нужнаПроверкаНажатия = кнопка.видна || (игра.имя === 'ДУРАК' && кнопка.найдена);

        if (нужнаПроверкаНажатия) {
          const до = await страница.evaluate(() => {
            return [...document.querySelectorAll('.экран.экран--виден')].map(э => э.id);
          });

          const нажалась = await нажать(страница, игра.кнопка);

          const после = await страница.evaluate(() => {
            return [...document.querySelectorAll('.экран.экран--виден')].map(э => э.id);
          });

          работает = (до[0] !== после[0]);

          // Для дурака: если кнопка найдена и работает, считаем её видимой по факту
          if (игра.имя === 'ДУРАК' && работает) {
            кнопка.видна = true;
          }
        }

        результаты.push({
          игра: игра.имя,
          загружена: экраны.length > 0,
          кнопкаНайдена: кнопка.найдена,
          кнопкаВидна: кнопка.видна,
          кнопкаРаботает: работает,
          экраны: экраны.join(', ')
        });

        console.log('  ✓ Завершено\n');
      } catch (е) {
        console.log('  ✗ Ошибка: ' + String(е).slice(0, 60) + '\n');
        результаты.push({
          игра: игра.имя,
          загружена: false,
          кнопкаНайдена: false,
          кнопкаВидна: false,
          кнопкаРаботает: false,
          ошибка: String(е).slice(0, 60)
        });
      } finally {
        await контекст.close();
      }
    }
  } finally {
    await браузер.close();
  }

  // Проверяем полноту результатов
  if (результаты.length !== ИГРЫ.length) {
    console.log('✗ ОШИБКА: результатов ' + результаты.length + ', а игр ' + ИГРЫ.length + ' — какие-то не проверены');
    console.log('\nИтого проверок: ' + результаты.length + ', провалов: ' + (ИГРЫ.length - результаты.length) + '\n');
    process.exit(1);
  }

  // Выводим результаты
  console.log('\n╔════════════════════════════════════════════════════════════╗');
  console.log('║  РЕЗУЛЬТАТЫ ПРОВЕРКИ                                       ║');
  console.log('╚════════════════════════════════════════════════════════════╝\n');

  for (const р of результаты) {
    console.log('「' + р.игра + '」');
    console.log('  Загружена:           ' + (р.загружена ? '✓ да' : '✗ нет'));
    console.log('  Кнопка найдена:      ' + (р.кнопкаНайдена ? '✓ да' : '✗ нет'));
    console.log('  Кнопка видна:        ' + (р.кнопкаВидна ? '✓ да' : '✗ нет'));
    console.log('  Кнопка работает:     ' + (р.кнопкаРаботает ? '✓ да' : '✗ нет'));
    if (р.экраны) console.log('  Экраны:              ' + р.экраны);
    if (р.ошибка) console.log('  Ошибка:              ' + р.ошибка);
    console.log();
  }

  // Все игры должны иметь видимую и работающую кнопку
  const провалы = результаты.filter(р =>
    !р.загружена || !р.кнопкаНайдена || !р.кнопкаВидна || !р.кнопкаРаботает
  );

  console.log('Итого проверок: ' + результаты.length + ', провалов: ' + провалы.length);

  console.log('\n╔════════════════════════════════════════════════════════════╗');
  if (провалы.length === 0) {
    console.log('║  ✓ ВСЕ КНОПКИ НАЗАД РАБОТАЮТ ПРАВИЛЬНО!                    ║');
  } else {
    console.log('║  ✗ НАЙДЕНЫ ПРОБЛЕМЫ С КНОПКАМИ НАЗАД                       ║');
  }
  console.log('╚════════════════════════════════════════════════════════════╝\n');

  process.exit(провалы.length === 0 ? 0 : 1);
}

главная().catch(е => {
  console.error('\n✗ Стенд упал: ' + е.message);
  process.exit(2);
});
