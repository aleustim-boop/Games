async function проверитьОднуИзОстальных(браузер, адрес, проверить, игра) {
  console.log('\n' + игра.имя + ' (' + игра.html + ')');
  const { контекст, страница, красные } = await новаяСтраница(браузер);
  try {
    await страница.goto(адрес + игра.html, { waitUntil: 'networkidle', timeout: 15000 });
    await спать(700);

    const узловНайдено = await страница.locator('#кнопка-лобби-назад').count().catch(() => 0);
    проверить(узловНайдено > 0, игра.имя + ': узел «‹» лобби (#кнопка-лобби-назад) найден в разметке');

    let итоговыйПуть = null;
    let ошибка = null;
    if (узловНайдено > 0) {
      try {
        await Promise.all([
          страница.waitForNavigation({ waitUntil: 'load', timeout: 8000 }),
          страница.locator('#кнопка-лобби-назад').first().click({ timeout: 5000 })
        ]);
        итоговыйПуть = new URL(страница.url()).pathname;
      } catch (сбой) {
        ошибка = String(сбой && сбой.message || сбой).slice(0, 150);
      }
    }

    const ведётНаВитрину = !!итоговыйПуть && итоговыйПуть.slice(-'index.html'.length) === 'index.html';
    проверить(ведётНаВитрину,
      игра.имя + ': «‹» с лобби уводит на index.html (витрину игр)' +
      (итоговыйПуть ? ' — получили: ' + итоговыйПуть
        : (ошибка ? ' — переход не удался: ' + ошибка : ' — не проверялось: узла не было')));

    проверить(красные.length === 0,
      игра.имя + ': консоль чистая' + (красные.length ? ' — ' + красные.slice(0, 3).join(' | ') : ''));
  } catch (сбой) {
    проверить(false, игра.имя + ': проверка сорвалась — ' + String(сбой && сбой.message || сбой).slice(0, 200));
  } finally {
    await контекст.close();
  }
}

/**
 * ЕДИНАЯ функция проверки — её же зовёт и чистый прогон (по настоящему
 * стенду), и ломающий (по стенду с испорченной копией). Ничего не решает
 * про process.exit — только считает и возвращает итог.
 */
async function проверитьКнопкиНазад(адрес) {
  const итог = { всего: 0, провалов: 0, строки: [] };
  function проверить(условие, текст) {
    итог.всего++;
    if (!условие) итог.провалов++;
    const строка = (условие ? '  ок    — ' : '  ПЛОХО — ') + текст;
    итог.строки.push(строка);
    console.log(строка);
  }

  const браузер = await chromium.launch();
  try {
    await проверитьДурака(браузер, адрес, проверить);
    for (const игра of ОСТАЛЬНЫЕ_ИГРЫ) {
      await проверитьОднуИзОстальных(браузер, адрес, проверить, игра);
    }
  } finally {
    await браузер.close();
  }
  return итог;
}

/* ---------------------------------------------------------------------
   Чистый запуск: свой стенд из настоящих файлов проекта (или внешний
   адрес доводом --адрес=).
   --------------------------------------------------------------------- */

async function главная() {
  console.log('\n╔════════════════════════════════════════════════════════════╗');
  console.log('║  ФИНАЛЬНАЯ ПРОВЕРКА: КНОПКИ «НАЗАД» У ВСЕХ ЧЕТЫРЁХ ИГР      ║');
  console.log('╚════════════════════════════════════════════════════════════╝');

  let свойСтенд = null;
  let адрес = ВНЕШНИЙ_АДРЕС;
  // Код выхода решаем ДО process.exit, а не внутри try: process.exit()
  // обрывает процесс мгновенно и finally после него не выполнится — стенд
  // и временные файлы (в ломающем запуске) останутся висеть. Поэтому здесь
  // process.exit — единственный, самый последний, уже ПОСЛЕ finally.
  let код = 2;
  try {
    if (адрес) {
      if (адрес.slice(-1) !== '/') адрес += '/';
      console.log('\nАдрес проверки (внешний): ' + адрес);
    } else {
      const порт = await свободныйПорт();
      свойСтенд = await поднятьСтенд(КОРЕНЬ_ПРОЕКТА, порт);
      адрес = 'http://127.0.0.1:' + порт + '/';
      console.log('\nСвой стенд поднят на настоящих файлах проекта: ' + адрес);
    }

    const итог = await проверитьКнопкиНазад(адрес);

    console.log('\nИтого проверок: ' + итог.всего + ', провалов: ' + итог.провалов);
    код = итог.провалов === 0 ? 0 : 1;
  } finally {
    if (свойСтенд) await погаситьСтенд(свойСтенд);
  }
  process.exit(код);
}

/* ---------------------------------------------------------------------
   Ломающий запуск: портим КОПИЮ во временной папке (файлы проекта не
   трогаем), поднимаем по ней свой стенд и гоняем ТУ ЖЕ проверитьКнопки
   Назад. Требуем провала — и требуем, чтобы покраснело именно там, где
   испортили, а не где попало.
   --------------------------------------------------------------------- */

function скопироватьПроектВоВременнуюПапку(tmp) {
  for (const имя of fs.readdirSync(КОРЕНЬ_ПРОЕКТА)) {
    if (имя.slice(-5) === '.html' || имя.slice(-4) === '.css') {
      fs.copyFileSync(path.join(КОРЕНЬ_ПРОЕКТА, имя), path.join(tmp, имя));
    }
  }
  fs.cpSync(path.join(КОРЕНЬ_ПРОЕКТА, 'js'), path.join(tmp, 'js'), { recursive: true });
  // Картинки и шрифты — не для поведения кнопок, а чтобы в консоли не было
  // лишних 404 (страница честно просит их при загрузке), которые иначе
  // засоряют «консоль чистая» и маскируют настоящую поломку под общим шумом.
  fs.cpSync(path.join(КОРЕНЬ_ПРОЕКТА, 'img'), path.join(tmp, 'img'), { recursive: true });
  fs.cpSync(path.join(КОРЕНЬ_ПРОЕКТА, 'шрифты'), path.join(tmp, 'шрифты'), { recursive: true });
}

/** Портит в копии кнопку «Назад» ЭКРАНА-ЛОББИ дурака (только её, не все 6 узлов). */
function сломатьДуракВКопии(tmp) {
  const файл = path.join(tmp, 'index.html');
  const исходный = fs.readFileSync(файл, 'utf-8');
  const было = 'data-путь="назад" aria-label="К выбору игры"';
  const стало = 'data-путь="назад-сломано" aria-label="К выбору игры"';
  if (исходный.indexOf(было) === -1) {
    throw new Error('испортитель дурака не нашёл кнопку «Назад» лобби в index.html — разметка уехала, чинить испортитель');
  }
  fs.writeFileSync(файл, исходный.replace(было, стало), 'utf-8');
  return файл;
}

/** Портит в копии id кнопки «‹» лобби у шашек — переименовывает его. */
function сломатьШашкиВКопии(tmp) {
  const файл = path.join(tmp, 'шашки.html');
  const исходный = fs.readFileSync(файл, 'utf-8');
  const было = 'id="кнопка-лобби-назад"';
  const стало = 'id="кнопка-лобби-назад-сломано"';
  if (исходный.indexOf(было) === -1) {
    throw new Error('испортитель шашек не нашёл id="кнопка-лобби-назад" в шашки.html — разметка уехала, чинить испортитель');
  }
  fs.writeFileSync(файл, исходный.replace(было, стало), 'utf-8');
  return файл;
}

async function главнаяЛомающая() {
  console.log('\n╔════════════════════════════════════════════════════════════╗');
  console.log('║  ЛОМАЮЩИЙ ЗАПУСК: проверка обязана покраснеть               ║');
  console.log('╚════════════════════════════════════════════════════════════╝');

  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'кнопки-назад-сломано-'));
  let стенд = null;
  // Код выхода решаем ДО process.exit — та же причина, что и в главная():
  // process.exit() внутри try обрывает процесс раньше finally, и стенд
  // с временной папкой остаются висеть (проверено: так и было до правки —
  // папки во временной директории не удалялись после ломающего запуска).
  let код = 2;
  try {
    скопироватьПроектВоВременнуюПапку(tmp);
    const файлДурака = сломатьДуракВКопии(tmp);
    const файлШашек = сломатьШашкиВКопии(tmp);
    console.log('\nВременная копия: ' + tmp);
    console.log('Испорчено:');
    console.log('  1) ' + файлДурака + ' — у кнопки «Назад» экрана-лобби дурака data-путь="назад" переименован в data-путь="назад-сломано"');
    console.log('  2) ' + файлШашек + ' — id="кнопка-лобби-назад" переименован в id="кнопка-лобби-назад-сломано"');

    const порт = await свободныйПорт();
    стенд = await поднятьСтенд(tmp, порт);
    const адрес = 'http://127.0.0.1:' + порт + '/';
    console.log('Стенд по испорченной копии: ' + адрес + '\n');

    const итог = await проверитьКнопкиНазад(адрес);

    console.log('\nИтого проверок на испорченной копии: ' + итог.всего + ', провалов: ' + итог.провалов);

    if (итог.провалов === 0) {
      console.log('\nПРОВЕРКА СЛЕПАЯ: испортили две дороги, а прогон прошёл целиком зелёным — ломающий запуск провален.');
      код = 1;
    } else {
      const покраснелоУДурака = итог.строки.some((с) => с.indexOf('ПЛОХО') !== -1 && с.indexOf('[лобби → «Назад»]') !== -1);
      const покраснелоУШашек = итог.строки.some((с) => с.indexOf('ПЛОХО') !== -1 && с.indexOf('ШАШКИ:') !== -1);
      console.log('\nПокраснело на дороге дурака «лобби → Назад»: ' + (покраснелоУДурака ? 'да' : 'НЕТ'));
      console.log('Покраснело на кнопке «‹» лобби у шашек: ' + (покраснелоУШашек ? 'да' : 'НЕТ'));

      if (!покраснелоУДурака || !покраснелоУШашек) {
        console.log('\nЛОМАЮЩИЙ ЗАПУСК ПРОВАЛЕН: провалы есть, но не там, где испортили, — проверка ловит не то, что нужно.');
        код = 1;
      } else {
        console.log('\nЛомающий запуск успешен: проверка честно покраснела ровно на обеих испорченных дорогах.');
        код = 0;
      }
    }
  } finally {
    if (стенд) await погаситьСтенд(стенд);
    fs.rmSync(tmp, { recursive: true, force: true });
  }
  process.exit(код);
}

