/* ---------------------------------------------------------------------
   Подъём и остановка стенда — тот же приём, что в других тестах папки
   (см. tests/шахматы-первый-взгляд.js): свой процесс node на локальный-
   сервер.js, корень раздачи — через переменную окружения КОРЕНЬ_СЕРВЕРА.
   Порт берём свободный (не 8790 — он боевой, там живут комнаты).
   --------------------------------------------------------------------- */

function свободныйПорт() {
  return new Promise((решить, отклонить) => {
    const пробник = net.createServer();
    пробник.on('error', отклонить);
    пробник.listen(0, '127.0.0.1', () => {
      const порт = пробник.address().port;
      пробник.close(() => решить(порт));
    });
  });
}

function поднятьСтенд(корень, порт) {
  return new Promise((решить, отклонить) => {
    const процесс = spawn(process.execPath, [
      path.join(__dirname, 'локальный-сервер.js'), String(порт)
    ], {
      cwd: __dirname,
      env: Object.assign({}, process.env, { КОРЕНЬ_СЕРВЕРА: корень }),
      stdio: 'pipe'
    });
    let вывод = '';
    const таймаут = setTimeout(() => отклонить(new Error('стенд не поднялся за 8 секунд')), 8000);
    процесс.stdout.on('data', (д) => {
      вывод += д.toString();
      if (вывод.indexOf('запущен') !== -1) { clearTimeout(таймаут); решить(процесс); }
    });
    процесс.stderr.on('data', (д) => console.log('  стенд (ошибка): ' + д.toString().trim()));
    процесс.on('error', (е) => { clearTimeout(таймаут); отклонить(е); });
    процесс.on('exit', (код) => {
      if (код !== null && код !== 0) { clearTimeout(таймаут); отклонить(new Error('стенд упал с кодом ' + код)); }
    });
  });
}

function погаситьСтенд(процесс) {
  return new Promise((решить) => {
    if (!процесс || процесс.killed) return решить();
    процесс.once('exit', () => решить());
    процесс.kill();
    setTimeout(решить, 1500);
  });
}

