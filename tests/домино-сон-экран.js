'use strict';
/* Домино: сон на экране (план штаб/план-сдача-голосованием.md, этап 12, С4).
   Что проверяем: (а) у спящего соседа на карточке класс «спит» и слова «играет бот», у неспящих
   ничего нет; (б) пока СПЛЮ Я (в корне вида `спит: true`), окно итогов раунда не лежит поверх
   плашки сна из листа «⋯» и возвращается, когда сон снят. Чистый node, браузера нет.

   Запуск:  node tests/домино-сон-экран.js
            node tests/домино-сон-экран.js --сломать
   Что делает:
     обычный запуск — НАСТОЯЩИЙ игры/домино/домино-экран.js на поддельной странице (узлы — по id из
     настоящего домино.html), настоящий видДляИгрока из server/игры/домино.js;
     --сломать — на КОПИЯХ экрана во временной папке системы (os.tmpdir()) портится по одной
     строке; копия обязана покраснеть именно на своей проверке. Строка для порчи должна найтись
     ровно один раз — ноль или два тоже провал. Настоящие файлы не трогаем.
   Код выхода: 0 — зелено; 1 — провал. */
const assert = require('node:assert/strict');
const path = require('node:path');
const os = require('node:os');
const fs = require('node:fs');
const vm = require('node:vm');
const { spawnSync } = require('node:child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const ЭКРАН = path.join(КОРЕНЬ, 'игры', 'домино', 'домино-экран.js');

function довод(имя) {
  const n = process.argv.indexOf(имя);
  return n > 0 ? path.resolve(process.argv[n + 1]) : null;
}
const ФАЙЛ_ЭКРАНА = довод('--экран') || ЭКРАН;
const ЛОМАТЬ = process.argv.includes('--сломать');

const Д = require(path.join(КОРЕНЬ, 'server', 'игры', 'домино.js'));
const П = require(path.join(КОРЕНЬ, 'игры', 'домино', 'домино-правила'));
const Б = require(path.join(КОРЕНЬ, 'игры', 'домино', 'домино-бот'));
const { сделатьДокумент, сделатьПамять, поддельныеЧасы } = require('./поддельный-браузер');
const МЕСТА = require(path.join(КОРЕНЬ, 'игры', 'дурак', 'game.js')).создатьПартию({ игроков: 4 }).игроки.slice();
const РАЗМЕТКА = fs.readFileSync(path.join(КОРЕНЬ, 'домино.html'), 'utf8');

let проверок = 0;
let провалов = 0;
function проверка(имя, дело) {
  проверок++;
  try { дело(); console.log('  ок      ' + имя); }
  catch (e) { провалов++; console.log('  ПРОВАЛ  ' + имя + ' — ' + (e && e.message)); }
}

/* Экран на поддельной странице: узлы — по id из настоящего домино.html. */
function запуститьЭкран() {
  const документ = сделатьДокумент();
  const память = сделатьПамять(false);
  const идентификаторы = [...new Set([...РАЗМЕТКА.matchAll(/\sid="([^"]+)"/g)].map(с => с[1]).concat(['дом-рейтинг', 'дом-профиль', 'кнопка-лобби-назад']))];
  assert.ok(идентификаторы.length > 50, 'в домино.html нашлось мало узлов: ' + идентификаторы.length);
  for (const id of идентификаторы) {
    const узел = документ.createElement('div');
    узел.id = id;
    if (id.startsWith('экран-') || id === 'дом-настройки') узел.className = 'экран';
    узел.open = false;
    узел.showModal = () => { узел.open = true; };
    узел.close = () => { узел.open = false; };
    документ.body.appendChild(узел);
    if (id === 'дом-итог-середина') узел.appendChild(документ.createElement('details'));
  }
  const окно = {
    document: документ, localStorage: память, addEventListener() {}, matchMedia: () => ({ matches: false }),
    ДоминоПравила: П, ДоминоБот: Б,
    ДоминоКости: { кость: () => документ.createElement('div'), цепь() {} },
    ДоминоПамять: { восстановить() { return null; } },
    ДеберцСказать: () => ({ открыть() {}, принять() {} }),
    ЛистЕщё: { подключить: () => ({ освежитьКнопкуНастроек() {}, открыт: () => false, закрыть() {}, открыть() {} }) },
    ЭкранРейтинга: { открыть() {}, открытьСчёт() {} },
    Телеграм: { показатьСтрелку() {} },
    Сеть: { отправитьХод: async () => ({ принято: true }), покинутьПартию() {} }
  };
  const песочница = {
    window: окно, document: документ, localStorage: память, location: { href: '' }, console,
    setTimeout, clearTimeout, setInterval: () => 0, Date: поддельныеЧасы(1000000).Дата, matchMedia: окно.matchMedia
  };
  vm.createContext(песочница);
  vm.runInContext(fs.readFileSync(ФАЙЛ_ЭКРАНА, 'utf8'), песочница, { filename: 'домино-экран.js' });
  const узел = id => документ.getElementById(id);
  return {
    узел,
    показать: вид => окно.ИграПоСети.показатьВид(вид),
    окноИтогаОткрыто: () => узел('дом-результат').open === true
  };
}

let номерВида = 0;
/* Вид стола, как его присылает сервер. Места 0..мест-1; «спящие» — номера мест (с нуля) с пометкой «спит»;
   «ясплю» — признак в корне вида (только у самого спящего). */
function видСтола({ мест = 3, спящие = [], ясплю = false, фаза = 'игра' } = {}) {
  const ключи = МЕСТА.slice(0, мест);   // настоящие ключи мест: по ним сервер считает номер места
  const п = Д.раздать(null, { игроки: ключи });
  const места = ключи.map((ключ, i) => ({ ключ, имя: i === 0 ? 'Вы' : 'Игрок ' + (i + 1), этоБот: false, хозяин: i === 0,
    наСвязи: true, ушёл: false, хочетЕщё: false, спит: спящие.includes(i) ? true : undefined }));
  const в = Д.видДляИгрока(п, ключи[0], { код: 'ТЕСТ', версия: ++номерВида, номерСобытия: 1, мест, мойНомер: 1, места });
  в.сыграноПартий = 0;
  if (фаза === 'итог') { в.домино.ход = 1; в.домино.фаза = 'итог'; }
  if (ясплю) в.спит = true;
  return в;
}
const МЕТКА = /играет бот/;
const карточка = (э, i) => {
  const у = э.узел('дом-игрок-' + i);
  assert.ok(у, 'нет карточки дом-игрок-' + i + ' — проверка не о том');
  return у;
};

console.log('Пометка у спящего соседа');

проверка('(1) сосед со «спит» — на карточке класс и слова «играет бот»', () => {
  const э = запуститьЭкран();
  э.показать(видСтола({ спящие: [1] }));
  const у = карточка(э, 1);
  assert.ok(у.classList.contains('дом-игрок--спит'), 'нет класса «дом-игрок--спит»: ' + у.className);
  const метки = у.querySelectorAll('.дом-игрок__бот');
  assert.equal(метки.length, 1, 'узлов пометки: ' + метки.length);
  assert.equal(метки[0].tagName.toLowerCase(), 'em');
  assert.match(метки[0].textContent, МЕТКА);
});

проверка('(2) неспящие соседи и я — без класса и без слов', () => {
  const э = запуститьЭкран();
  э.показать(видСтола({ спящие: [1] }));
  for (const i of [0, 2]) {
    const у = карточка(э, i);
    assert.ok(!у.classList.contains('дом-игрок--спит'), 'карточка ' + i + ' помечена классом');
    assert.doesNotMatch(у.textContent, МЕТКА, 'в карточке ' + i + ' слова про бота');
  }
});

проверка('(3) спящих нет — ни у кого нет пометки', () => {
  const э = запуститьЭкран();
  э.показать(видСтола({ мест: 4 }));
  for (let i = 0; i < 4; i++) {
    const у = карточка(э, i);
    assert.ok(!у.classList.contains('дом-игрок--спит'), 'карточка ' + i + ' помечена классом');
    assert.doesNotMatch(у.textContent, МЕТКА, 'в карточке ' + i + ' слова про бота');
  }
});

проверка('(4) проснулся — пометка уходит со следующим видом', () => {
  const э = запуститьЭкран();
  э.показать(видСтола({ спящие: [2] }));
  assert.ok(карточка(э, 2).classList.contains('дом-игрок--спит'), 'пометка не появилась — проверка не о том');
  э.показать(видСтола({}));
  assert.ok(!карточка(э, 2).classList.contains('дом-игрок--спит'), 'класс остался');
  assert.doesNotMatch(карточка(э, 2).textContent, МЕТКА, 'слова остались');
});

