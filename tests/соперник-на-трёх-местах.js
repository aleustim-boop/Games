function сколькоНайдено(текст, найти) { return текст.split(найти).length - 1; }

const ПОРЧИ = [
  { имя: 'на 3+ местах пропажа снова «Соперник …»',
    найти: 'застольеБольшеДвоих(вид))', заменить: 'false)',
    // ищем ровно в вызове текстПропажи, чтобы совпадение было одно
    контекст: 'соперникПропалС, застольеБольшеДвоих(вид))' },
  { имя: '«вышли из игры» на 3+ местах снова «Соперник вышел…»',
    найти: 'застольеБольшеДвоих(вид) ? ТЕКСТ_ОСТАЛЬНЫЕ_ВЫШЛИ', заменить: 'false ? ТЕКСТ_ОСТАЛЬНЫЕ_ВЫШЛИ' },
  { имя: '«думает» на 3+ местах снова читает имяСоперника',
    найти: 'застольеБольшеДвоих(вид) ? кемЗоветсяХодящий(вид) : (вид.имяСоперника', заменить: 'false ? кемЗоветсяХодящий(вид) : (вид.имяСоперника' },
  { имя: 'сломана строка «думает»: слово «думает» стало «ждёт»',
    найти: "показатьСвязь(кто + ' думает…'", заменить: "показатьСвязь(кто + ' ждёт…'" },
  { имя: 'без ходящего вместо «Игрок» стоит «Соперник»',
    найти: ": 'Игрок';\n  }", заменить: ": 'Соперник';\n  }", перевод: true },
  { имя: 'ходящего берут без проверки «ходит === true»',
    найти: 'место.ходит === true && место.имя', заменить: 'место.ходит && место.имя' },
  { имя: 'на двоих слова поменялись («Остальные» вместо «Соперник» в тексте пропажи)',
    найти: 'return мягко ? ТЕКСТ_ДРУГ_ПЕРЕПОДКЛЮЧАЕТСЯ : ТЕКСТ_ДРУГ_ПРОПАЛ;',
    заменить: 'return мягко ? ТЕКСТ_ОСТАЛЬНЫЕ_ПЕРЕПОДКЛЮЧАЮТСЯ : ТЕКСТ_ОСТАЛЬНЫЕ_ПРОПАЛИ;' }
];

/** Применить порчу к тексту; не ровно одно совпадение — выход 2. */
function испортить(исходник, п) {
  const где = п.контекст || п.найти;
  const искомое = п.перевод ? где.replace(/\n/g, исходник.indexOf('\r\n') !== -1 ? '\r\n' : '\n') : где;
  if (сколькоНайдено(исходник, искомое) !== 1) {
    console.log('НЕ НАШЛОСЬ ровно один раз: ' + п.имя);
    process.exit(2);
  }
  if (п.контекст) {
    return исходник.split(п.контекст).join(п.контекст.replace(п.найти, п.заменить));
  }
  const на = п.перевод ? п.заменить.replace(/\n/g, исходник.indexOf('\r\n') !== -1 ? '\r\n' : '\n') : п.заменить;
  return исходник.split(искомое).join(на);
}

function сломать() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'соперник-на-трёх-'));
  console.log('Ломающий запуск: копии в ' + папка);
  let слепых = 0;
  for (let i = 0; i < ПОРЧИ.length; i++) {
    const п = ПОРЧИ[i];
    const копия = path.join(папка, i + '-сеть.js');
    fs.writeFileSync(копия, испортить(ИСХОДНИК, п), 'utf8');
    const итог = spawnSync(process.execPath, [__filename, '--сеть', копия], { encoding: 'utf8' });
    const первый = (итог.stdout || '').split('\n').filter(function (с) { return с.indexOf('ПЛОХО') !== -1; })[0] || '';
    // Покраснение — только код 1. Код 4 (падение) — не покраснение.
    if (итог.status === 1) console.log('  покраснела — ' + п.имя + '  [' + первый.trim() + ']');
    else { слепых++; console.log('  СЛЕПА (код ' + итог.status + ') — ' + п.имя); }
  }
  console.log('Порч: ' + ПОРЧИ.length + ', слепых: ' + слепых);
  process.exit(слепых ? 3 : 0);
}

try {
  if (process.argv.indexOf('--сломать') !== -1) сломать();
  else главное();
} catch (ошибка) {
  console.log('ПАДЕНИЕ проверки: ' + (ошибка && ошибка.message || ошибка));
  process.exit(4);
}
