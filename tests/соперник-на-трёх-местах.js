/* =====================================================================
   НА СТОЛЕ ОТ ТРЁХ МЕСТ СЛОВА «СОПЕРНИК» НЕТ (js/сеть.js)

   Чистый node: из настоящего js/сеть.js вырезаются нужные функции
   (освежитьСтрокуСвязи, текстПропажи, кемЗоветсяХодящий, застольеБольшеДвоих)
   и константы текстов, и выполняются в песочнице vm с поддельными
   переменными состояния. Что не нашлось — проверка падает (ноль найденного
   — провал, а не пропуск).

   Что проверяется:
     - 2 места: слова прежние, байт в байт («Соперник …», имяСоперника в «думает»);
     - 3 и 4 места: «пропал», «переподключается», «вышел» — «Остальные игроки …»;
       поле имяСоперника ('Соперник' как у домино/катана/монополии/покера
       или 'Друг' как у деберца) в строках не читается: слов «оперник»
       и «Друг» нет;
     - 3 места, «думает»: имя берётся у места из «застолом» с ходит === true
       и непустым именем, иначе «Игрок думает…».

   Запуск:
       node tests/соперник-на-трёх-местах.js
       node tests/соперник-на-трёх-местах.js --сеть <копия сеть.js>
   Ломающий запуск (обязан покраснеть на каждой порче):
       node tests/соперник-на-трёх-местах.js --сломать
     Порча делается в КОПИИ сеть.js во временной папке, файл проекта
     не трогается.
   Выход: 0 — зелено; 1 — провал проверок; 2 — место порчи не нашлось
   ровно один раз; 3 — какая-то порча не дала провала (проверка слепа);
   4 — ПАДЕНИЕ проверки (исключение). Ломающий запуск код 4 за покраснение
   не считает: упавшая проверка не доказала, что умеет краснеть.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const vm = require('vm');
const { spawnSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const НАСТОЯЩАЯ_СЕТЬ = path.join(КОРЕНЬ, 'js', 'сеть.js');

function довод(имя) {
  const и = process.argv.indexOf(имя);
  return и !== -1 ? process.argv[и + 1] : null;
}

const ФАЙЛ_СЕТИ = довод('--сеть') || НАСТОЯЩАЯ_СЕТЬ;
const ИСХОДНИК = fs.readFileSync(ФАЙЛ_СЕТИ, 'utf8');

let проверок = 0;
let провалов = 0;
function проверить(условие, слова) {
  проверок++;
  if (!условие) провалов++;
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
}

/** Вырезать функцию, стоящую внутри обёртки сети (отступ два пробела). */
function вырезатьФункцию(имя) {
  const от = ИСХОДНИК.indexOf('\n  function ' + имя + '(');
  if (от === -1) throw new Error('в js/сеть.js не найдена функция «' + имя + '» — проверка слепа');
  const конец = /\r?\n  \}\r?\n/g;
  конец.lastIndex = от;
  const н = конец.exec(ИСХОДНИК);
  if (!н) throw new Error('у функции «' + имя + '» не найден конец');
  return ИСХОДНИК.slice(от, н.index + н[0].length);
}

/** Вырезать строку «const ИМЯ = …;» (в одну строку). */
function вырезатьКонстанту(имя) {
  const м = new RegExp('\\n  const ' + имя + ' = [^\\n]*;').exec(ИСХОДНИК);
  if (!м) throw new Error('в js/сеть.js не найдена константа «' + имя + '» — проверка слепа');
  return м[0];
}

/**
 * Песочница с вырезанным кодом. Возвращает функцию «строка(вид, мсПропажи)»
 * — что показала бы строка связи на этом состоянии стола.
 */
function собрать() {
  const код = [
    вырезатьКонстанту('МЯГКАЯ_ПРОПАЖА'),
    вырезатьКонстанту('ТЕКСТ_ДРУГ_ПЕРЕПОДКЛЮЧАЕТСЯ'),
    вырезатьКонстанту('ТЕКСТ_ДРУГ_ПРОПАЛ'),
    вырезатьКонстанту('ТЕКСТ_ОСТАЛЬНЫЕ_ПЕРЕПОДКЛЮЧАЮТСЯ'),
    вырезатьКонстанту('ТЕКСТ_ОСТАЛЬНЫЕ_ПРОПАЛИ'),
    вырезатьКонстанту('ТЕКСТ_ОСТАЛЬНЫЕ_ВЫШЛИ'),
    вырезатьФункцию('текстПропажи'),
    вырезатьФункцию('кемЗоветсяХодящий'),
    вырезатьФункцию('застольеБольшеДвоих'),
    вырезатьФункцию('освежитьСтрокуСвязи')
  ].join('\n');
  const показано = [];
  const песок = {
    вПартии: true, связьЕсть: true, когдаОтвечалСервер: 0, МОЛЧАНИЕ_ЭТО_ОБРЫВ: 35000,
    попытокПодряд: 0, последнееСостояние: null, соперникПропалС: 0,
    приветствиеДо: 0, когдаБылоСобытие: 0, ДОЛГОЕ_РАЗДУМЬЕ: 1000,
    показатьСвязь: function (текст) { показано.push(String(текст)); },
    Date: { now: function () { return 100000; } },
    Array: Array
  };
  vm.runInNewContext(код + '\nglobalThis.__строка = освежитьСтрокуСвязи;', песок, { filename: ФАЙЛ_СЕТИ });
  return {
    строка: function (вид, ещёСкольковТомуНазадПропал) {
      показано.length = 0;
      песок.последнееСостояние = вид;
      песок.соперникПропалС = ещёСкольковТомуНазадПропал === undefined ? 0 : 100000 - ещёСкольковТомуНазадПропал;
      песок.__строка();
      return показано.length ? показано[показано.length - 1] : '';
    }
  };
}

/** Вид стола на сколько-то мест (число мест — по портретам, как у сервера). */
function вид(мест, имя, свойства) {
  const в = { портреты: new Array(мест).fill('п'), соперникНаСвязи: true, соперникУшёл: false, яХожу: false, завершена: false };
  if (имя) в.имяСоперника = имя;
  return Object.assign(в, свойства || {});
}

const Ш = /оперник|Друг/;

function главное() {
  const с = собрать();
  console.log('Сеть: ' + ФАЙЛ_СЕТИ);

  console.log('\nНа двоих — слова прежние, байт в байт');
  проверить(с.строка(вид(2, 'Аня', { соперникНаСвязи: false }), 1000) === 'Соперник переподключается…',
    'пропал недавно: «Соперник переподключается…»');
  проверить(с.строка(вид(2, 'Аня', { соперникНаСвязи: false }), 30000) === 'Соперник пропал со связи — ждём, партия сохранена',
    'пропал давно: «Соперник пропал со связи…»');
  проверить(с.строка(вид(2, 'Аня', { соперникУшёл: true })) === 'Соперник вышел из игры',
    'вышел: «Соперник вышел из игры»');
  проверить(с.строка(вид(2, 'Аня')) === 'Аня думает…', 'думает, имя есть: «Аня думает…»');
  проверить(с.строка(вид(2, '')) === 'Соперник думает…', 'думает, имени нет: «Соперник думает…»');

  for (const мест of [3, 4]) {
    for (const слово of ['Соперник', 'Друг']) {
      console.log('\nНа ' + мест + ' местах, имяСоперника = «' + слово + '» — слов «соперник» и «Друг» нет');
      const случаи = [
        ['переподключаются', { соперникНаСвязи: false }, 1000, 'Остальные игроки переподключаются…'],
        ['пропали', { соперникНаСвязи: false }, 30000, 'Остальные игроки пропали со связи — ждём, партия сохранена'],
        ['вышли', { соперникУшёл: true }, undefined, 'Остальные игроки вышли из игры']
      ];
      for (const [назв, свойства, мс, ждём] of случаи) {
        const итог = с.строка(вид(мест, слово, свойства), мс);
        проверить(итог === ждём && !Ш.test(итог), '«' + назв + '»: ' + итог);
      }
      const думает = с.строка(вид(мест, слово));
      проверить(думает === 'Игрок думает…' && !Ш.test(думает), '«думает», застолья нет: ' + думает);
    }
  }

  console.log('\nНа 3 местах — «думает» по списку застолом');
  const места = [
    { имя: 'Аня', ходит: false }, { имя: 'Боря', ходит: true }, { имя: 'Вера', ходит: false }
  ];
  const сХодящим = с.строка(вид(3, 'Соперник', { застолом: места }));
  проверить(сХодящим === 'Боря думает…', 'ходит Боря: ' + сХодящим);
  const безИмени = с.строка(вид(3, 'Соперник', {
    застолом: [{ имя: 'Аня', ходит: false }, { имя: '', ходит: true }, { имя: 'Вера', ходит: false }]
  }));
  проверить(безИмени === 'Игрок думает…', 'ходящий без имени: ' + безИмени);
  const никтоНеХодит = с.строка(видТрёх(места.map(function (м) { return { имя: м.имя, ходит: false }; })));
  проверить(никтоНеХодит === 'Игрок думает…', 'ходящего в списке нет: ' + никтоНеХодит);
  const ходитТолькоПохожее = с.строка(видТрёх([{ имя: 'Аня', ходит: 'да' }, { имя: 'Боря' }, { имя: 'Вера' }]));
  проверить(ходитТолькоПохожее === 'Игрок думает…', 'ходит не true, а «да»: ' + ходитТолькоПохожее);

  function видТрёх(застолом) { return вид(3, 'Друг', { застолом: застолом }); }

  проверить(проверок >= 25, 'не выпал ни один случай: проверок ' + проверок + ' (порог 25)');
  console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
}

