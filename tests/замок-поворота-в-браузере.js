'use strict';

/* =====================================================================
   ЗАМОК ПОВОРОТА: СТОЛ НЕ ДОЛЖЕН ЛОЖИТЬСЯ НАБОК.

   Владелец попросил запретить поворот: в полном экране игра занимает
   весь телефон, и случайный поворот кладёт стол набок целиком.
   С Bot API 8.0 у Telegram для этого есть lockOrientation().

   Главная тонкость, ради которой стенд и написан. lockOrientation()
   запирает ТЕКУЩУЮ ориентацию — ту, в которой телефон держат в этот миг.
   Значит, звать его вслепую нельзя: если игру открыли, держа телефон
   боком, замок запрёт именно бок, и человек уже не сможет повернуть
   телефон стоймя. Правильное поведение: стоймя — запираем сразу; боком —
   ждём, пока повернут, и запираем тогда.

   Сама ориентация подделке неизвестна: игра узнаёт её у браузера
   (matchMedia «(orientation: portrait)», запасной способ — сравнить
   высоту окна с шириной). Поэтому «повернуть телефон» здесь — это
   поменять размер окна.

   Что проверяем:
     1) узкое окно (телефон стоймя) — замок повешен один раз;
     2) ШИРОКОЕ окно (телефон боком) — замка НЕТ вовсе, игра ждёт;
     3) окно из широкого стало узким — замок повешен, и ровно один;
     4) клиент без методов замка — ничего не падает, консоль чистая;
     5) старый Telegram (7.10) — замок не трогаем;
     6) дверь наружу: обычныйПоворот() отпирает, замок больше не висит.

   Запуск (страничный сервер уже поднят):
       node tests/замок-поворота-в-браузере.js
       node tests/замок-поворота-в-браузере.js 8080
   ===================================================================== */

const { chromium, подготовитьПодделку } = require('./браузер-робот.js');

const ПОРТ = Number(process.argv[2]) || 8080;
const АДРЕС = 'http://127.0.0.1:' + ПОРТ + '/';

let провалов = 0;
function проверить(условие, слова) {
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}

/* Красные строки консоли. Отказ загрузки настоящего telegram-web-app.js —
   наших рук дело (мы не пускаем его, чтобы он не затёр подделку). */
function ловецОшибок(страница) {
  const красные = [];
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
    красные.push('консоль: ' + м.text());
  });
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  return красные;
}

async function показания(страница) {
  return страница.evaluate(() => ({
    замков: window.__дневник ? window.__дневник.замковПоворота : -1,
    отпираний: window.__дневник ? window.__дневник.отпираний : -1,
    заперт: !!(window.Telegram && window.Telegram.WebApp.isOrientationLocked),
    вертикаль: window.matchMedia('(orientation: portrait)').matches,
    окно: window.innerWidth + '×' + window.innerHeight,
    состояние: window.Телеграм && window.Телеграм.состояние ? window.Телеграм.состояние() : null
  }));
}

(async () => {
  const браузер = await chromium.launch();
  console.log('Замок поворота. Страница: ' + АДРЕС);

  /* ================================================================
     1. Телефон стоймя — запираем сразу
     ================================================================ */
  console.log('\n=== 1. Телефон держат стоймя (390×844) ===');
  {
    const окно = await браузер.newContext({ viewport: { width: 390, height: 844 } });
    const страница = await окно.newPage();
    const красные = ловецОшибок(страница);
    await подготовитьПодделку(страница, { версия: '8.0', полныйЭкран: 'дают', поворот: 'умеет' });
    await страница.goto(АДРЕС);
    await страница.waitForTimeout(600);

    const п = await показания(страница);
    console.log('  окно ' + п.окно + ', браузер говорит «вертикаль»: ' + п.вертикаль);
    проверить(п.замков === 1, 'замок повешен ровно один раз (замков: ' + п.замков + ')');
    проверить(п.заперт, 'Telegram считает поворот запертым');
    проверить(красные.length === 0, 'консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));
    await окно.close();
  }

  /* ================================================================
     2. Телефон держат боком — замка быть не должно
     ================================================================ */
  console.log('\n=== 2. Игру открыли, держа телефон боком (844×390) ===');
  {
    const окно = await браузер.newContext({ viewport: { width: 844, height: 390 } });
    const страница = await окно.newPage();
    const красные = ловецОшибок(страница);
    await подготовитьПодделку(страница, { версия: '8.0', полныйЭкран: 'дают', поворот: 'умеет' });
    await страница.goto(АДРЕС);
    await страница.waitForTimeout(600);

    const п = await показания(страница);
    console.log('  окно ' + п.окно + ', браузер говорит «вертикаль»: ' + п.вертикаль);
    проверить(п.вертикаль === false, 'браузер и правда считает окно лежачим (иначе проверка бессмысленна)');
    проверить(п.замков === 0,
      'замок НЕ повешен: боком запирать нельзя, иначе телефон навсегда останется набок (замков: ' + п.замков + ')');
    проверить(!п.заперт, 'Telegram поворот не запирал');
    if (п.состояние && п.состояние.ждёмВертикаль !== undefined) {
      проверить(п.состояние.ждёмВертикаль === true,
        'игра честно говорит, что ждёт вертикали: ждёмВертикаль = ' + п.состояние.ждёмВертикаль);
    }

    /* ---- 3. Телефон повернули стоймя ---- */
    console.log('\n=== 3. Тот же телефон повернули стоймя (390×844) ===');
    await страница.setViewportSize({ width: 390, height: 844 });
    await страница.waitForTimeout(400);
    /* Вторая пара глаз: игра проверяет поворот и по событиям Telegram —
       на случай, если браузерные события в окне-обёртке не дойдут. */
    await страница.evaluate(() => {
      (window.__дневник.события.viewportChanged || []).forEach((ф) => ф());
      (window.__дневник.события.safeAreaChanged || []).forEach((ф) => ф());
    });
    await страница.waitForTimeout(300);

    const после = await показания(страница);
    console.log('  окно ' + после.окно + ', браузер говорит «вертикаль»: ' + после.вертикаль);
    проверить(после.замков === 1, 'после поворота замок повешен, и ровно один раз (замков: ' + после.замков + ')');
    проверить(после.заперт, 'Telegram считает поворот запертым');

    /* И ещё раз туда-сюда: второго замка вешать не надо, он уже висит. */
    await страница.setViewportSize({ width: 844, height: 390 });
    await страница.waitForTimeout(300);
    await страница.setViewportSize({ width: 390, height: 844 });
    await страница.waitForTimeout(300);
    const ещёРаз = await показания(страница);
    проверить(ещёРаз.замков === 1, 'лишних просьб запереть не было даже после двух поворотов (замков: ' + ещёРаз.замков + ')');
    проверить(красные.length === 0, 'консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));

    /* ---- 6. Дверь наружу: отпереть ---- */
    console.log('\n=== 6. Ручная дверь: отпереть поворот ===');
    const отпёрли = await страница.evaluate(() =>
      (window.Телеграм && window.Телеграм.отперетьПоворот) ? window.Телеграм.отперетьПоворот() : 'двери нет');
    await страница.waitForTimeout(200);
    const итог = await показания(страница);
    if (отпёрли === 'двери нет') {
      console.log('  (двери «отперетьПоворот» в window.Телеграм нет — проверять нечего)');
    } else {
      проверить(отпёрли === true, 'дверь ответила «да»');
      проверить(итог.отпираний === 1 && !итог.заперт,
        'поворот отпёрт: отпираний ' + итог.отпираний + ', заперт ' + итог.заперт);
    }
    проверить(красные.length === 0, 'консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));
    await окно.close();
  }

  /* ================================================================
     4. Клиент без методов замка
     ================================================================ */
  console.log('\n=== 4. Telegram 8.0, но методов замка нет вовсе ===');
  {
    const окно = await браузер.newContext({ viewport: { width: 390, height: 844 } });
    const страница = await окно.newPage();
    const красные = ловецОшибок(страница);
    await подготовитьПодделку(страница, { версия: '8.0', полныйЭкран: 'дают', поворот: 'нет метода' });
    await страница.goto(АДРЕС);
    await страница.waitForTimeout(600);

    const методы = await страница.evaluate(() => ({
      запереть: typeof window.Telegram.WebApp.lockOrientation,
      отпереть: typeof window.Telegram.WebApp.unlockOrientation
    }));
    проверить(методы.запереть === 'undefined' && методы.отпереть === 'undefined',
      'подделка и правда без методов замка: ' + JSON.stringify(методы));
    const п = await показания(страница);
    проверить(п.замков === 0 && !п.заперт, 'ничего не заперто и никто не упал');
    проверить(красные.length === 0, 'ни падений, ни красных строк' + (красные.length ? ': ' + красные.join(' | ') : ''));

    // Игра должна остаться играбельной
    await страница.click('#кнопка-игра-дурак'); await страница.waitForTimeout(200);
    await страница.click('#кнопка-режим-бот'); await страница.waitForTimeout(200);
    await страница.click('#кнопка-играть'); await страница.waitForTimeout(800);
    const карт = await страница.evaluate(() => document.querySelectorAll('#карты-человека .карта').length);
    проверить(карт >= 6, 'партия всё равно начинается, карт на руке: ' + карт);
    await окно.close();
  }

  /* ================================================================
     5. Старый Telegram
     ================================================================ */
  console.log('\n=== 5. Telegram 7.10 — замка не просим ===');
  {
    const окно = await браузер.newContext({ viewport: { width: 390, height: 844 } });
    const страница = await окно.newPage();
    const красные = ловецОшибок(страница);
    // Нарочно злая подделка: методы ЕСТЬ, а версия старая — игра обязана смотреть на версию
    await подготовитьПодделку(страница, { версия: '7.10', полныйЭкран: 'дают', поворот: 'умеет' });
    await страница.goto(АДРЕС);
    await страница.waitForTimeout(600);

    const п = await показания(страница);
    проверить(п.замков === 0, 'на старой версии замок не просили (замков: ' + п.замков + ')');
    проверить(!п.заперт, 'поворот не заперт');
    проверить(красные.length === 0, 'консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));
    await окно.close();
  }

  await браузер.close();
  console.log('\nИтог: провалов ' + провалов);
  process.exit(провалов ? 1 : 0);
})().catch((о) => { console.error('Стенд упал: ' + (о && о.stack || о)); process.exit(2); });
