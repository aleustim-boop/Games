/* ============================================================
   Проверка: адрес картинки, который js кладёт в CSS-переменную,
   не зависит от того, в какой папке лежит css.

   ЗАЧЕМ. Когда js пишет узел.style.setProperty('--значок', 'url("img/…")'),
   а css-файл подставляет это через var(--значок), браузер считает
   короткий путь «img/…» от папки ТОГО CSS-ФАЙЛА, а не от страницы.
   Пока style.css лежал в корне, это совпадало. После переезда в
   общее/css/ экран «Рейтинг» на боевом сайте стал просить
   «общее/css/img/рейтинг/шахматы@2x.png» — значки пропали у игроков.
   Лечится полным адресом: new URL(путь, document.baseURI).href.

   ЧТО ДЕЛАЕТ. Обычный node, без браузера. Читает все js из папок
   «общее/» и «игры/», находит каждое setProperty('--…', …url(…)…) и по
   тексту выясняет, откуда берётся адрес: раскрывает переменные
   (const адрес = …) и функции (function картинкаРейтинга…) на несколько
   шагов вглубь, в том числе из соседних файлов. Место зелёное, если:
     — по дороге адрес приведён к полному через «new URL(»;
     — либо адрес приходит только из доверенного источника полных
       адресов (список ДОВЕРЕННЫЕ ниже) и нигде по дороге нет строки,
       начинающейся с «img/».
   Всё остальное — красное, в том числе «не смогла понять, откуда адрес»:
   непонятное считаем поломкой, а не пропуском.
   Доверенные источники проверка тоже перепроверяет по их тексту.
   Ноль найденных мест — провал: значит, поиск сломался или приём
   переименовали, и проверка стала украшением.

   ЧЕГО НЕ ВИДИТ. Адрес, который собирается не в том же вызове
   setProperty (например, готовая строка 'url(…)' пришла в переменной
   из другого места), и inline-стиль без переменной (backgroundImage =)
   — у него путь считается от страницы, там короткий путь верен.

   ЗАПУСК
     node tests/картинки-из-переменных-от-корня.js
     node tests/картинки-из-переменных-от-корня.js --корень=<папка>
   Второй вид — для ломающего запуска: в <папка> лежит КОПИЯ с той же
   структурой (общее/js/…), в которой починка убрана; проверка обязана
   покраснеть. Настоящие файлы проекта не портим.
   Код выхода: 0 — всё зелёное, 1 — есть красное.
   ============================================================ */
'use strict';

const fs = require('fs');
const path = require('path');

const доводКорня = process.argv.find(function (а) { return а.indexOf('--корень=') === 0; });
const КОРЕНЬ = доводКорня ? path.resolve(доводКорня.slice('--корень='.length)) : path.join(__dirname, '..');
const ПАПКИ = ['общее', 'игры'];
const ГЛУБИНА = 4;

/* Источники, которые отдают только полный адрес. У каждого — способ
   убедиться в этом по тексту: доверие без перепроверки протухает. */
const ДОВЕРЕННЫЕ = {
  'фотоИгрока': {
    почему: 'общее/js/telegram.js пропускает только адреса, начинающиеся с https://',
    подтвердить: function (файлы) {
      const телеграм = файлы.find(function (ф) { return ф.имя === 'общее/js/telegram.js'; });
      if (!телеграм) return 'нет файла общее/js/telegram.js';
      const тело = телаФункции('фотоИгрока', [телеграм]).join('\n');
      if (!тело) return 'в общее/js/telegram.js нет функции фотоИгрока';
      if (!/indexOf\(\s*'https:\/\/'\s*\)\s*!==\s*0/.test(тело)) return 'фотоИгрока в telegram.js больше не отсеивает адреса не с https://';
      return '';
    },
  },
  'адресФотоПоКлючу': {
    почему: 'адрес сервера комнат (с доменом) + «/фото/» + ключ',
    подтвердить: function (файлы) {
      const тело = телаФункции('адресФотоПоКлючу', файлы).join('\n');
      if (!тело) return 'не нашла функцию адресФотоПоКлючу';
      if (тело.indexOf("'/фото/'") === -1 || !/адресСервера\s*\(/.test(тело)) return 'адресФотоПоКлючу больше не собирает адрес как «адрес сервера + /фото/»';
      return '';
    },
  },
};

/* Слова языка и встроенные функции: их раскрывать незачем. */
const НЕ_РАСКРЫВАТЬ = new Set(['if', 'for', 'while', 'switch', 'catch', 'return', 'typeof', 'function', 'new',
  'String', 'Number', 'Boolean', 'URL', 'Math', 'Object', 'Array', 'JSON', 'encodeURI', 'encodeURIComponent',
  'padStart', 'trim', 'indexOf', 'slice', 'join', 'map', 'test', 'toString', 'concat', 'replace']);

const БУКВА = '[\\p{L}_$]';
const ЗНАК_ИМЕНИ = '[\\p{L}\\p{N}_$]';

function экранировать(строка) { return строка.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }

/** Все js-файлы под папкой, с путём через прямой слэш от корня. */
function собратьФайлы(папка, относительно, куда) {
  let записи;
  try { записи = fs.readdirSync(папка, { withFileTypes: true }); } catch (сбой) { return; }
  записи.forEach(function (з) {
    const полный = path.join(папка, з.name);
    const имя = относительно + '/' + з.name;
    if (з.isDirectory()) собратьФайлы(полный, имя, куда);
    else if (/\.js$/.test(з.name)) куда.push({ имя: имя, текст: fs.readFileSync(полный, 'utf8') });
  });
}

/**
 * Идёт по тексту от открывающей скобки и возвращает место парной
 * закрывающей. Строки и комментарии пропускает: в 'url("' скобка
 * не настоящая. Не нашла пару — -1.
 */
function парнаяСкобка(текст, с) {
  const открытые = { '(': ')', '{': '}', '[': ']' };
  const стопка = [];
  for (let i = с; i < текст.length; i++) {
    const з = текст[i];
    if (з === '/' && текст[i + 1] === '/') { const к = текст.indexOf('\n', i); if (к === -1) return -1; i = к; continue; }
    if (з === '/' && текст[i + 1] === '*') { const к = текст.indexOf('*/', i + 2); if (к === -1) return -1; i = к + 1; continue; }
    if (з === "'" || з === '"' || з === '`') {
      let j = i + 1;
      while (j < текст.length && текст[j] !== з) { if (текст[j] === '\\') j++; j++; }
      i = j;
      continue;
    }
    if (открытые[з]) { стопка.push(открытые[з]); continue; }
    if (з === ')' || з === '}' || з === ']') {
      if (стопка.pop() !== з) return -1;
      if (стопка.length === 0) return i;
    }
  }
  return -1;
}

/** Конец выражения: первая «;» вне скобок, строк и комментариев. */
function конецВыражения(текст, с) {
  for (let i = с; i < текст.length; i++) {
    const з = текст[i];
    if (з === ';') return i;
    if (з === '(' || з === '{' || з === '[') { const к = парнаяСкобка(текст, i); if (к === -1) return Math.min(текст.length, с + 2000); i = к; continue; }
    if (з === "'" || з === '"' || з === '`') {
      let j = i + 1;
      while (j < текст.length && текст[j] !== з) { if (текст[j] === '\\') j++; j++; }
      i = j;
    }
  }
  return текст.length;
}

/** Код без содержимого строк: остаются только имена и знаки. */
function безСтрок(код) {
  return код
    .replace(/'(?:\\.|[^'\\])*'|"(?:\\.|[^"\\])*"/g, "''")
    .replace(/`(?:\\.|[^`\\])*`/g, function (шаблон) {
      const вставки = шаблон.match(/\$\{[^}]*\}/g) || [];
      return вставки.map(function (в) { return в.slice(2, -1); }).join(' + ') || "''";
    });
}

/** Тексты всех функций с таким именем в данных файлах. */
function телаФункции(имя, файлы) {
  const и = экранировать(имя);
  const образцы = [
    new RegExp('function\\s+' + и + '\\s*\\(', 'gu'),
    new RegExp('(?<![.\\p{L}\\p{N}_$])' + и + '\\s*\\([^()]*\\)\\s*\\{', 'gu'),
    new RegExp('(?<![.\\p{L}\\p{N}_$])' + и + '\\s*[:=]\\s*(?:function\\s*)?(?:\\([^()]*\\)|' + БУКВА + ЗНАК_ИМЕНИ + '*)\\s*=>', 'gu'),
    new RegExp('(?<![.\\p{L}\\p{N}_$])' + и + '\\s*[:=]\\s*function\\s*\\(', 'gu'),
  ];
  const тела = [];
  const виденные = new Set();
  файлы.forEach(function (ф) {
    образцы.forEach(function (образец) {
      образец.lastIndex = 0;
      let н;
      while ((н = образец.exec(ф.текст))) {
        const ключ = ф.имя + ':' + н.index;
        if (виденные.has(ключ)) continue;
        виденные.add(ключ);
        const скобка = ф.текст.indexOf('{', н.index + имя.length);
        const точка = конецВыражения(ф.текст, н.index + н[0].length);
        /* Стрелка без фигурных скобок — тело до «;». */
        if (скобка === -1 || (н[0].indexOf('=>') !== -1 && !/^\s*\{/.test(ф.текст.slice(н.index + н[0].length)))) {
          тела.push(ф.текст.slice(н.index, точка));
          continue;
        }
        const конец = парнаяСкобка(ф.текст, скобка);
        тела.push(ф.текст.slice(н.index, конец === -1 ? Math.min(ф.текст.length, скобка + 4000) : конец + 1));
      }
    });
  });
  return тела;
}

/**
 * Раскрывает выражение: к его тексту дописывает тексты объявлений
 * переменных и функций, из которых оно собрано. Доверенные источники
 * не раскрывает — только отмечает, что они встретились.
 */
function раскрыть(код, файл, позиция, файлы, глубина, виденные, доверенныеВстретились) {
  let итог = код;
  if (глубина <= 0) return итог;
  const чистый = безСтрок(код);

  const вызовы = new RegExp('(?<!' + ЗНАК_ИМЕНИ + ')(' + БУКВА + ЗНАК_ИМЕНИ + '*)\\s*(?:\\?\\.)?\\s*\\(', 'gu');
  const имена = new RegExp('(?<![.' + '\\p{L}\\p{N}_$])(' + БУКВА + ЗНАК_ИМЕНИ + '*)(?!\\s*(?:\\?\\.)?\\s*\\(|' + ЗНАК_ИМЕНИ + ')', 'gu');
  let н;

  while ((н = вызовы.exec(чистый))) {
    const имя = н[1];
    if (ДОВЕРЕННЫЕ[имя]) { доверенныеВстретились.add(имя); continue; }
    if (НЕ_РАСКРЫВАТЬ.has(имя) || виденные.has('ф:' + имя)) continue;
    виденные.add('ф:' + имя);
    let тела = телаФункции(имя, [файл]);
    let гдеИскали = файл;
    if (!тела.length) { тела = телаФункции(имя, файлы); гдеИскали = null; }
    тела.forEach(function (тело) {
      /* У тела из чужого файла своих соседних объявлений не ищем: позиция неизвестна. */
      итог += '\n' + раскрыть(тело, гдеИскали || файл, гдеИскали ? файл.текст.length : -1, файлы, глубина - 1, виденные, доверенныеВстретились);
    });
  }

  if (позиция >= 0) {
    while ((н = имена.exec(чистый))) {
      const имя = н[1];
      if (НЕ_РАСКРЫВАТЬ.has(имя) || виденные.has('п:' + файл.имя + ':' + имя)) continue;
      виденные.add('п:' + файл.имя + ':' + имя);
      const объявление = new RegExp('(?:const|let|var)\\s+' + экранировать(имя) + '\\s*=', 'gu');
      let последнее = null;
      let о;
      while ((о = объявление.exec(файл.текст)) && о.index < позиция) последнее = о;
      if (!последнее) continue;
      const начало = последнее.index + последнее[0].length;
      const значение = файл.текст.slice(начало, конецВыражения(файл.текст, начало));
      итог += '\n' + раскрыть(значение, файл, последнее.index, файлы, глубина - 1, виденные, доверенныеВстретились);
    }
  }
  return итог;
}

/** Все места setProperty('--имя', значение-с-url) в файле. */
function местаВФайле(файл) {
  const места = [];
  const образец = /setProperty\s*\(/g;
  let н;
  while ((н = образец.exec(файл.текст))) {
    const открытие = н.index + н[0].length - 1;
    const закрытие = парнаяСкобка(файл.текст, открытие);
    if (закрытие === -1) continue;
    const внутри = файл.текст.slice(открытие + 1, закрытие);
    const разбор = /^\s*['"`](--[^'"`]+)['"`]\s*,/.exec(внутри);
    if (!разбор) continue;
    const значение = внутри.slice(разбор[0].length);
    if (значение.indexOf('url(') === -1) continue;
    места.push({
      файл: файл,
      строка: файл.текст.slice(0, н.index).split('\n').length,
      позиция: н.index,
      переменная: разбор[1],
      значение: значение.trim(),
    });
  }
  return места;
}

/* ---------- сама проверка ---------- */

const файлы = [];
ПАПКИ.forEach(function (п) { собратьФайлы(path.join(КОРЕНЬ, п), п, файлы); });

const провалы = [];
let зелёных = 0;

console.log('Корень: ' + КОРЕНЬ);
console.log('Файлов js в «общее/» и «игры/»: ' + файлы.length);

const места = [];
файлы.forEach(function (ф) { местаВФайле(ф).forEach(function (м) { места.push(м); }); });
console.log('Мест setProperty(\'--…\', …url(…)): ' + места.length + '\n');

if (места.length === 0) {
  провалы.push('не нашла ни одного setProperty(\'--…\', …url(…)) — поиск сломан или приём переименовали; ноль найденного — провал');
}

const нужныеДоверенные = new Set();

места.forEach(function (м) {
  const доверенныеТут = new Set();
  const цепочка = раскрыть(м.значение, м.файл, м.позиция, файлы, ГЛУБИНА, new Set(), доверенныеТут);
  const приведёнКПолному = /new\s+URL\s*\(/.test(цепочка);
  const естьКороткийПуть = /['"`](?:\.{1,2}\/)*img\//.test(цепочка);
  const подпись = м.файл.имя + ':' + м.строка + ' ' + м.переменная;

  let вывод;
  let хорошо = false;
  if (приведёнКПолному) {
    хорошо = true;
    вывод = 'адрес приведён к полному через new URL';
  } else if (естьКороткийПуть) {
    вывод = 'в переменную уходит короткий путь «img/…» без new URL — браузер посчитает его от папки css-файла';
  } else if (доверенныеТут.size) {
    хорошо = true;
    доверенныеТут.forEach(function (д) { нужныеДоверенные.add(д); });
    вывод = 'адрес только из доверенных источников: ' + Array.from(доверенныеТут).join(', ');
  } else {
    вывод = 'не смогла понять, откуда адрес (ни new URL, ни доверенного источника) — считаю поломкой';
  }

  console.log((хорошо ? '  ок    ' : '  ПРОВАЛ ') + подпись + ' — ' + вывод);
  if (хорошо) зелёных++; else провалы.push(подпись + ' — ' + вывод + '; значение: ' + м.значение);
});

/* Доверие перепроверяем по тексту источника. */
нужныеДоверенные.forEach(function (имя) {
  const беда = ДОВЕРЕННЫЕ[имя].подтвердить(файлы);
  if (беда) {
    console.log('  ПРОВАЛ доверенный источник «' + имя + '» — ' + беда);
    провалы.push('доверенный источник «' + имя + '» не подтвердился: ' + беда);
  } else {
    console.log('  ок    доверенный источник «' + имя + '» подтверждён: ' + ДОВЕРЕННЫЕ[имя].почему);
  }
});

console.log('\nМест: ' + места.length + ', зелёных: ' + зелёных);
console.log('Итого проверок: ' + (места.length + нужныеДоверенные.size + 1) + ', провалов: ' + провалы.length);
if (провалы.length) {
  провалы.forEach(function (п) { console.log('  - ' + п); });
  process.exit(1);
}
process.exit(0);
