/** Нужен ли стенду настоящий браузер. */
function этоБраузерный(имя) {
  const текст = fs.readFileSync(path.join(ПАПКА, имя), 'utf8');
  return текст.indexOf('браузер-робот') !== -1 || текст.indexOf('chromium') !== -1;
}

/** Все проверки по порядку. */
function собратьСписок() {
  const все = fs.readdirSync(ПАПКА)
    .filter(function (имя) { return имя.slice(-3) === '.js'; })
    .sort(function (а, б) { return а.localeCompare(б, 'ru'); });
  const сначала = все.filter(function (имя) { return ПОСЛЕДНИМИ.indexOf(имя) === -1; });
  const потом = все.filter(function (имя) { return ПОСЛЕДНИМИ.indexOf(имя) !== -1; });
  return сначала.concat(потом);
}

