// Проверка «на страницах игр есть настоящий текст для поисковиков» (привлечение, этап 4.4).
// Поисковик читает страницу без скриптов и видит пустой каркас, поэтому в <body> каждой
// из восьми страниц лежит один блок <noscript>: заголовок, правила, частые вопросы, ссылка на бота.
// Без браузера. Запуск: node tests/текст-для-поисковиков.js [--корень=<папка-копия>]
// Ломающий запуск: node tests/текст-для-поисковиков.js --сломать
//   портит КОПИИ страниц во временной папке системы (настоящие файлы не трогает)
//   и требует, чтобы проверка на каждой порче покраснела.
const fs = require('fs');
const os = require('os');
const path = require('path');

const СТРАНИЦЫ = ['index.html', 'шашки.html', 'шахматы.html', 'нарды.html', 'домино.html',
  'деберц.html', 'морской-бой.html', 'монополия.html'];
const ССЫЛКА_НА_БОТА = 'https://t.me/BoardingGames_bot';
const МИНИМУМ_ЗНАКОВ = 600;
const МИНИМУМ_ВОПРОСОВ = 4;

let корень = path.join(__dirname, '..');
let сломать = false;
for (const довод of process.argv.slice(2)) {
  if (довод.startsWith('--корень=')) корень = path.resolve(довод.substring('--корень='.length));
  if (довод === '--сломать') сломать = true;
}

// Текст без тегов, с одиночными пробелами
function безТегов(разметка) {
  return разметка.replace(/<[^>]*>/g, ' ').replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();
}

// Проверяет одну папку; возвращает { проверок, провалы }
function проверитьПапку(папка) {
  let проверок = 0;
  const провалы = [];
  const проверить = (условие, сообщение) => { проверок++; if (!условие) провалы.push('  ' + сообщение); };

  const найденныеТексты = [];
  let найденоСтраниц = 0;
  for (const файл of СТРАНИЦЫ) {
    const полный = path.join(папка, файл);
    if (!fs.existsSync(полный)) { проверить(false, файл + ': страницы нет на диске'); continue; }
    найденоСтраниц++;
    const текст = fs.readFileSync(полный, 'utf8');
    const блоки = текст.match(/<noscript[\s\S]*?<\/noscript>/gi) || [];
    проверить(блоки.length === 1, файл + ': блоков noscript ' + блоки.length + ', нужен ровно один');
    // Нет блока — дальше проверять нечего, но провал уже записан строкой выше.
    if (блоки.length !== 1) continue;
    const блок = блоки[0];
    const чистый = безТегов(блок);
    проверить(/<h1[\s>]/i.test(блок), файл + ': в noscript нет h1');
    проверить(/<h1[^>]*>[^<]*онлайн с друзьями в Telegram/.test(блок),
      файл + ': h1 без слов «онлайн с друзьями в Telegram»');
    проверить(чистый.length >= МИНИМУМ_ЗНАКОВ,
      файл + ': текста ' + чистый.length + ' знаков, нужно не меньше ' + МИНИМУМ_ЗНАКОВ);

    // Раздел частых вопросов: h2, дальше пары h3 + p
    const места = блок.split(/<h2[^>]*>\s*Частые вопросы\s*<\/h2>/);
    проверить(места.length === 2, файл + ': раздела «Частые вопросы» нет или он не один');
    const вопросы = места.length === 2 ? места[1].match(/<h3[^>]*>[^<]+<\/h3>\s*<p>[^<]+<\/p>/g) || [] : [];
    проверить(вопросы.length >= МИНИМУМ_ВОПРОСОВ,
      файл + ': вопросов с ответами ' + вопросы.length + ', нужно не меньше ' + МИНИМУМ_ВОПРОСОВ);

    проверить(блок.includes('href="' + ССЫЛКА_НА_БОТА + '"'), файл + ': нет ссылки на бота ' + ССЫЛКА_НА_БОТА);
    найденныеТексты.push({ файл, чистый });
  }
  // Ноль найденных страниц — это провал, а не пропуск
  проверить(найденоСтраниц === СТРАНИЦЫ.length, 'найдено страниц ' + найденоСтраниц + ' из ' + СТРАНИЦЫ.length);

  // Первая часть (до «Частых вопросов») у каждой страницы своя
  const вступления = найденныеТексты.map(т => т.чистый.split('Частые вопросы')[0]);
  проверить(new Set(вступления).size === вступления.length && вступления.length === СТРАНИЦЫ.length,
    'тексты страниц должны быть разными: найдены одинаковые вступления');
  return { проверок, провалы };
}

function вывести(итог, подпись) {
  for (const п of итог.провалы) console.log(п);
  console.log('Итого проверок: ' + итог.проверок + ', провалов: ' + итог.провалы.length);
}

// Ломающий запуск: каждая порча — копия во временной папке
function сломатьИПроверить() {
  const порчи = [
    ['убрать блок noscript с одной страницы', т => т.replace(/<noscript[\s\S]*?<\/noscript>/i, '')],
    ['удвоить блок noscript', т => т.replace(/<noscript[\s\S]*?<\/noscript>/i, м => м + м)],
    ['убрать h1', т => т.replace(/<h1[\s\S]*?<\/h1>/i, '')],
    ['убрать ссылку на бота', т => т.split(ССЫЛКА_НА_БОТА).join('https://example.com')],
    ['оставить два вопроса', т => т.replace(/<h3>(Можно ли играть с ботом|Это бесплатно)\?<\/h3>\s*<p>[^<]*<\/p>/g, '')],
    ['сократить текст до пары слов', т => т.replace(/<noscript[\s\S]*?<\/noscript>/i,
      '<noscript><h1>Игра онлайн с друзьями в Telegram</h1><h2>Частые вопросы</h2></noscript>')],
  ];
  let непокрасневшие = 0;
  for (const [название, порча] of порчи) {
    const копия = fs.mkdtempSync(path.join(os.tmpdir(), 'текст-поисковиков-'));
    for (const файл of СТРАНИЦЫ) fs.copyFileSync(path.join(корень, файл), path.join(копия, файл));
    const цель = path.join(копия, СТРАНИЦЫ[1]);
    fs.writeFileSync(цель, порча(fs.readFileSync(цель, 'utf8')));
    const итог = проверитьПапку(копия);
    const покраснела = итог.провалы.length > 0;
    console.log((покраснела ? 'КРАСНЕЕТ ' : 'НЕ КРАСНЕЕТ ') + '— ' + название + ' (провалов ' + итог.провалы.length + ')');
    if (!покраснела) непокрасневшие++;
    fs.rmSync(копия, { recursive: true, force: true });
  }
  // Одинаковые тексты на двух страницах: копируем блок одной страницы в другую
  const копия = fs.mkdtempSync(path.join(os.tmpdir(), 'текст-поисковиков-'));
  for (const файл of СТРАНИЦЫ) fs.copyFileSync(path.join(корень, файл), path.join(копия, файл));
  const блок = /<noscript[\s\S]*?<\/noscript>/i.exec(fs.readFileSync(path.join(копия, СТРАНИЦЫ[1]), 'utf8'))[0];
  const вторая = path.join(копия, СТРАНИЦЫ[2]);
  fs.writeFileSync(вторая, fs.readFileSync(вторая, 'utf8').replace(/<noscript[\s\S]*?<\/noscript>/i, () => блок));
  const итог = проверитьПапку(копия);
  console.log((итог.провалы.length ? 'КРАСНЕЕТ ' : 'НЕ КРАСНЕЕТ ') + '— одинаковый текст на двух страницах (провалов ' + итог.провалы.length + ')');
  if (!итог.провалы.length) непокрасневшие++;
  fs.rmSync(копия, { recursive: true, force: true });

  if (непокрасневшие) { console.log('ПРОВАЛ: ' + непокрасневшие + ' порч проверка не заметила'); process.exit(1); }
  console.log('Ломающий запуск: все порчи замечены');
}

if (сломать) {
  сломатьИПроверить();
} else {
  const итог = проверитьПапку(корень);
  вывести(итог, 'Текст для поисковиков');
  if (итог.провалы.length) process.exit(1);
}
