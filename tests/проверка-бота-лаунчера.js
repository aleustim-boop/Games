/* =====================================================================
   Проверка бота-лаунчера: понятно ли он ругается, когда настройки
   не заполнены, и не падает ли «красной простынёй».

   ВАЖНО: настоящий bot/.env мы не читаем и не запускаем — там живой токен
   пользователя. Вместо этого копируем сам bot/бот.js на отдельный стенд
   во временной папке и подкладываем ему СВОИ файлы настроек. Бот читает
   .env рядом с собой, поэтому на стенде он видит только наши подделки.

   Запуск: node tests/проверка-бота-лаунчера.js
   ===================================================================== */

'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const ИСХОДНЫЙ_БОТ = path.join(КОРЕНЬ, 'bot', 'бот.js');
const ОБРАЗЕЦ = path.join(КОРЕНЬ, 'bot', '.env.example');

const СТЕНД = fs.mkdtempSync(path.join(os.tmpdir(), 'проверка-бота-'));
fs.copyFileSync(ИСХОДНЫЙ_БОТ, path.join(СТЕНД, 'бот.js'));
if (fs.existsSync(ОБРАЗЕЦ)) fs.copyFileSync(ОБРАЗЕЦ, path.join(СТЕНД, '.env.example'));

const беды = [];
let проверок = 0;

/** Запустить бота на стенде с заданным содержимым .env (null — файла нет). */
function запустить(настройки, секунд) {
  const файл = path.join(СТЕНД, '.env');
  if (настройки === null) { if (fs.existsSync(файл)) fs.unlinkSync(файл); }
  else fs.writeFileSync(файл, настройки, 'utf8');

  const итог = spawnSync(process.execPath, [path.join(СТЕНД, 'бот.js')], {
    cwd: СТЕНД, encoding: 'utf8', timeout: (секунд || 15) * 1000
  });
  return {
    код: итог.status,
    вывод: ((итог.stdout || '') + (итог.stderr || '')).trim(),
    поТаймауту: итог.signal === 'SIGTERM'
  };
}

/** Похоже ли это на «красную простыню» — необработанное падение Node. */
function этоПадение(текст) {
  return /\bat .*\(.*:\d+:\d+\)|Node\.js v\d|throw err;|UnhandledPromiseRejection|ReferenceError|TypeError:/.test(текст);
}

function случай(название, настройки, ожидаемыеСлова) {
  проверок++;
  const р = запустить(настройки);
  const где = 'случай «' + название + '»';

  if (р.поТаймауту) { беды.push(где + ': бот завис и не завершился за 15 секунд'); return р; }
  if (этоПадение(р.вывод)) {
    беды.push(где + ': бот упал с технической ошибкой вместо понятного объяснения.\n      ' +
      р.вывод.split('\n').slice(0, 4).join('\n      '));
    return р;
  }
  if (р.код === 0) беды.push(где + ': бот завершился как будто всё хорошо (код 0), хотя настройки плохие');
  for (const слово of ожидаемыеСлова) {
    if (р.вывод.toLowerCase().indexOf(слово.toLowerCase()) === -1) {
      беды.push(где + ': в объяснении нет слова «' + слово + '». Вывод был:\n      ' +
        р.вывод.split('\n').slice(0, 6).join('\n      '));
      break;
    }
  }
  // Объяснение должно быть по-русски и не пустое.
  if (!/[а-яё]/i.test(р.вывод)) беды.push(где + ': объяснение не на русском либо пустое');
  return р;
}

console.log('=== Проверка бота-лаунчера ===');
console.log('стенд: ' + СТЕНД);
console.log('(настоящий bot/.env не читается и не запускается)\n');

const р1 = случай('файла настроек нет вообще', null, ['не нашёл файл', '.env', 'BotFather']);
console.log('1. Настроек нет  — код ' + р1.код + ', первая строка: «' + р1.вывод.split('\n')[0] + '»');

const р2 = случай('пустой файл настроек', '\n\n# только пояснения\n', ['токен', 'BOT_TOKEN']);
console.log('2. Пустой файл   — код ' + р2.код + ', первая строка: «' + р2.вывод.split('\n')[0] + '»');

if (fs.existsSync(path.join(СТЕНД, '.env.example'))) {
  const образец = fs.readFileSync(path.join(СТЕНД, '.env.example'), 'utf8');
  const р3 = случай('образец скопировали, но ничего не вписали', образец, ['токен']);
  console.log('3. Образец как есть — код ' + р3.код + ', первая строка: «' + р3.вывод.split('\n')[0] + '»');
}

const р4 = случай('токен без двоеточия', 'BOT_TOKEN=простослова\nGAME_URL=https://example.com/\n',
  ['токен', 'двоеточие']);
console.log('4. Кривой токен  — код ' + р4.код + ', первая строка: «' + р4.вывод.split('\n')[0] + '»');

/* --- Почему выдуманные токены собраны из кусочков, а не написаны строкой ---

   Дело не в тайне: значения ниже придуманы и ни к какому боту не подходят.
   Дело в том, что GitHub узнаёт токены Telegram «по лицу» — по внешнему виду
   строки. Увидев в файле строку нужного вида, он присылает владельцу
   репозитория тревожное письмо про утечку секрета. Письмо ложное, но пугает.

   Поэтому в тексте файла целой строки-«токена» нет: она склеивается уже
   во время работы. Боту при этом достаётся ровно то же значение, что и
   раньше, и проверка не изменилась ни на шаг. */
function выдуманныйТокен(хвост) {
  const номерБота = [1, 2, 3, 4, 5, 6, 7, 8, 9, 0].join('');  // десять цифр, как у настоящего
  return номерБота + ':' + хвост;
}

// Случаи 5 и 6: до Telegram дело не дойдёт, бот выйдет раньше — на пустом
// адресе игры и на адресе без https. Здесь от токена нужно одно: двоеточие.
const ТОКЕН_ЛИШЬ_БЫ_С_ДВОЕТОЧИЕМ = выдуманныйТокен('ABC' + 'def' + 'GHI' + 'jkl' + 'MNO' + 'pqrs');

const р5 = случай('нет адреса игры', 'BOT_TOKEN=' + ТОКЕН_ЛИШЬ_БЫ_С_ДВОЕТОЧИЕМ + '\n', ['адрес', 'GAME_URL']);
console.log('5. Нет адреса    — код ' + р5.код + ', первая строка: «' + р5.вывод.split('\n')[0] + '»');

const р6 = случай('адрес не https',
  'BOT_TOKEN=' + ТОКЕН_ЛИШЬ_БЫ_С_ДВОЕТОЧИЕМ + '\nGAME_URL=http://localhost:8123/\n', ['https']);
console.log('6. Адрес не https — код ' + р6.код + ', первая строка: «' + р6.вывод.split('\n')[0] + '»');

/* Случай 7: настройки формально верные, но бот выдуман. Здесь длина и вид
   хвоста важны: только на строку привычного вида Telegram отвечает «401 —
   не признал», а нам нужна именно эта ветка бота. Хвост из 35 знаков,
   как у настоящего токена, но склеенный из повторов слова «fake». */
const ТОКЕН_КОТОРЫЙ_ОТВЕРГНУТ = выдуманныйТокен('AAH' + 'fake'.repeat(8));

проверок++;
const р7 = запустить('BOT_TOKEN=' + ТОКЕН_КОТОРЫЙ_ОТВЕРГНУТ + '\nGAME_URL=https://example.com/\n', 40);
console.log('7. Выдуманный токен — код ' + р7.код + ', первая строка: «' + (р7.вывод.split('\n')[0] || '(пусто)') + '»');
if (р7.поТаймауту) {
  беды.push('случай «выдуманный токен»: бот не завершился за 40 секунд и не сказал, что не так');
} else if (этоПадение(р7.вывод)) {
  беды.push('случай «выдуманный токен»: вместо объяснения техническая ошибка:\n      ' +
    р7.вывод.split('\n').slice(0, 5).join('\n      '));
} else if (р7.вывод.indexOf('не признал токен') !== -1) {
  console.log('   (бот дошёл до Telegram и получил отказ — проверена та самая ветка «токен не тот»)');
} else {
  // Честно отмечаем: без интернета до нужной ветки не добраться, но и падения нет.
  console.log('   (до Telegram дозвониться не вышло — проверено только то, что бот не упал ' +
              'и объяснился словами; ветку «токен не тот» этот запуск не проверил)');
}

// Уборка за собой
try {
  for (const имя of fs.readdirSync(СТЕНД)) fs.unlinkSync(path.join(СТЕНД, имя));
  fs.rmdirSync(СТЕНД);
} catch (ошибка) { /* временная папка не критична */ }

console.log('\nпроверок: ' + проверок);
if (беды.length === 0) {
  console.log('=== Итог: бот на любые кривые настройки отвечает понятным текстом и не падает ===');
  process.exit(0);
}
console.log('НАЙДЕНО:');
беды.forEach(function (т) { console.log('  - ' + т); });
console.log('=== Итог: бед ' + беды.length + ' ===');
process.exit(1);
