'use strict';
/* =====================================================================
   Постоянная проверка: реванш парного стола, когда один человек вышел
   после конца партии, обязан вернуть стол в прихожую («ждём четвёртого»),
   а не начинать новую партию втроём. Перенесена из временного скрипта
   разработчика (коммит 739838f, «опись-реванш.js» во временной папке
   сессии) в постоянную папку tests/.

   Сервер — модулем, без порта, без записи на диск. Боты ускорены только
   в памяти этого процесса.

   Запуск:
       node tests/реванш-парами-без-четвёртого.js
   Ломающий прогон (проверить, что тест умеет краснеть):
       node tests/реванш-парами-без-четвёртого.js --сломать
   «--сломать» подменяет ответ сервера на ушедшего игрока так, будто
   сервер (по старой ошибке) молча согласился на обычный реванш втроём
   вместо возврата в прихожую, — и сверка обязана заметить подмену.
   ===================================================================== */
const path = require('path');
const дурак = require(path.join(__dirname, '..', 'server', 'игры', 'дурак.js'));
дурак.темпБота.обычный = 1;
дурак.темпБота.внеОчереди = 1;
const комнаты = require(path.join(__dirname, '..', 'server', 'комнаты.js'));

const ЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;
if (ЛОМАТЬ) {
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: ответ сервера на ушедшего игрока подменяется на обычный реванш — проверка обязана покраснеть ***');
}

function вид(код, пропуск) {
  const н = комнаты.найтиИгрока(код, пропуск);
  return комнаты.показатьИгроку(н.комната, н.ктоЯ);
}
function ход(код, пропуск, намерение) {
  const н = комнаты.найтиИгрока(код, пропуск);
  return комнаты.сделатьХод(н.комната, н.ктоЯ, намерение);
}
/* Простейший игрок: отбиться чем получится, иначе сходить, иначе «беру»/«бито». */
function сходить(код, пропуск) {
  const в = вид(код, пропуск);
  if (в.этап !== 'игра' || !в.яХожу) return;
  const рука = в.мояРука.length;
  if (в.яОтбиваюсь) {
    for (let п = 0; п < в.стол.length; п++) {
      if (в.стол[п].защита) continue;
      for (let к = 0; к < рука; к++) {
        if (ход(код, пропуск, { действие: 'отбить', пара: п, карта: к }).принято) return;
      }
    }
    if (ход(код, пропуск, { действие: 'беру' }).принято) return;
  }
  for (let к = 0; к < рука; к++) {
    if (ход(код, пропуск, { действие: 'ходить', карта: к }).принято) return;
  }
  ход(код, пропуск, { действие: 'бито' });
}
function доиграть(код, игроки) {
  return new Promise(function (готово) {
    let шагов = 0;
    (function шаг() {
      шагов++;
      for (const пропуск of игроки) сходить(код, пропуск);
      const в = вид(код, игроки[0]);
      if (в.этап === 'конец' || шагов > 20000) return готово(в);
      setTimeout(шаг, 2);
    })();
  });
}

/* В ломающем запуске подменяем ответ сервера так, будто он (по старой
   ошибке) молча согласился на обычный реванш, а стол остался как был. */
function испортитьОтветЕслиНадо(ответ) {
  if (!ЛОМАТЬ) return ответ;
  return Object.assign({}, ответ, { событие: 'реванш' });
}
function испортитьВидЕслиНадо(в) {
  if (!ЛОМАТЬ) return в;
  return Object.assign({}, в, { этап: 'игра', можноНачать: true });
}

(async function () {
  let провалов = 0;
  let проверок = 0;
  function проверить(да, слова) {
    проверок++;
    if (!да) провалов++;
    console.log((да ? 'ок    ' : 'ПЛОХО ') + слова);
  }

  // Парный стол: хозяин, друг, два бота
  const с = комнаты.создатьКомнату('3.3.3.1', { мест: 4, парами: true, имя: 'Хозяин' });
  const д = комнаты.войтиВКомнату(с.код, { имя: 'Друг', метка: 'меткаДруга12345' });
  ход(с.код, с.пропуск, { действие: 'бот' });
  ход(с.код, с.пропуск, { действие: 'бот' });
  проверить(ход(с.код, с.пропуск, { действие: 'начать' }).принято, 'партия парами началась');
  const итог = await доиграть(с.код, [с.пропуск, д.пропуск]);
  проверить(итог.этап === 'конец', 'партия доиграна (этап ' + итог.этап + ')');

  // Друг вышел после конца партии
  const н = комнаты.найтиИгрока(с.код, д.пропуск);
  комнаты.выйти(н.комната, н.ктоЯ);
  const ответ = испортитьОтветЕслиНадо(ход(с.код, с.пропуск, { действие: 'ещё' }));
  const после = испортитьВидЕслиНадо(вид(с.код, с.пропуск));
  console.log('«ещё» после ухода друга: ' + JSON.stringify(ответ));
  проверить(ответ.событие === 'ждём-четвёртого', 'сервер ответил «ждём четвёртого»');
  проверить(после.этап === 'ожидание', 'стол вернулся в прихожую (этап ' + после.этап + ')');
  проверить(после.застолом.length === 3 && после.можноНачать === false,
    'за столом трое, «Начать» не горит (сидит ' + после.застолом.length + ', можноНачать ' + после.можноНачать + ')');
  проверить(после.событие === 'Для игры 2 на 2 нужны четверо — ждём четвёртого игрока', 'текст события: ' + после.событие);

  // Контроль: никто не вышел — обычный реванш
  const к = комнаты.создатьКомнату('3.3.3.2', { мест: 4, парами: true, имя: 'Хозяин' });
  for (let i = 0; i < 3; i++) ход(к.код, к.пропуск, { действие: 'бот' });
  ход(к.код, к.пропуск, { действие: 'начать' });
  const итог2 = await доиграть(к.код, [к.пропуск]);
  проверить(итог2.этап === 'конец', 'вторая партия доиграна');
  const ответ2 = ход(к.код, к.пропуск, { действие: 'ещё' });
  проверить(ответ2.событие === 'реванш', 'без ушедших — обычный реванш (' + ответ2.событие + ')');

  console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
})();
