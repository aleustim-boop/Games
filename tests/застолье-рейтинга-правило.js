'use strict';

/* =====================================================================
   ЗАСТОЛЬЕ ДЛЯ РЕЙТИНГА: ПОЛЕ ПЕРЕВОДНОЙ.

   Что проверяем. Функция застольеДляРейтинга (server/комнаты.js) добавляет
   поле переводной в результат для каждого игрока. Поле нужно рейтингу,
   чтобы вести отдельный счёт по правилу партии (подкидной/переводной).

   Проверяем:
     — если комната.переводной === true → результат содержит переводной: true
     — если комната.переводной === false → результат содержит переводной: false
     — если комната.переводной undefined → результат содержит переводной: false
       (из-за === true в коде)

   Запуск:
       node tests/застолье-рейтинга-правило.js
   ===================================================================== */

const path = require('path');
const комнаты = require(path.join(__dirname, '..', 'server', 'комнаты.js'));

let провалов = 0;
let проверок = 0;

function проверить(описание, условие) {
  проверок++;
  if (!условие) {
    console.log('  ✗ ' + описание);
    провалов++;
  } else {
    console.log('  ✓ ' + описание);
  }
}

/**
 * Создать минимальный mock объект комнаты для тестирования
 * застольеДляРейтинга.
 */
function создатьМокКомнату(параметры) {
  параметры = параметры || {};
  return {
    мест: 2,  // количество мест за столом (МЕСТА берётся из партии-по-сети.js)
    партия: {
      завершена: true,
      ничья: false,
      проигравшие: ['бот']  // имя места проигравшего игрока
    },
    игроки: {
      'человек': {
        телеграм: 12345,
        имя: 'Игрок 0',
        этоБот: false,
        уровень: 'обычный'
      },
      'бот': {
        телеграм: 67890,
        имя: 'Игрок 1',
        этоБот: true,
        уровень: 'обычный'
      }
    },
    парами: параметры.парами !== undefined ? параметры.парами : false,
    переводной: параметры.переводной !== undefined ? параметры.переводной : undefined,
    уровеньБотов: 'обычный'
  };
}


/**
 * ТЕСТ 1: переводной = true
 */
console.log('Тест 1: комната.переводной = true');
const комната1 = создатьМокКомнату({ переводной: true });
const результат1 = комнаты.застольеДляРейтинга(комната1);
проверить('человек имеет переводной: true', результат1[0].переводной === true);
проверить('бот имеет переводной: true', результат1[1].переводной === true);
проверить('результат содержит 2 игроков', результат1.length === 2);

/**
 * ТЕСТ 2: переводной = false
 */
console.log('\nТест 2: комната.переводной = false');
const комната2 = создатьМокКомнату({ переводной: false });
const результат2 = комнаты.застольеДляРейтинга(комната2);
проверить('человек имеет переводной: false', результат2[0].переводной === false);
проверить('бот имеет переводной: false', результат2[1].переводной === false);

/**
 * ТЕСТ 3: переводной = undefined (должен быть false)
 */
console.log('\nТест 3: комната.переводной = undefined (не задан)');
const комната3 = создатьМокКомнату({ переводной: undefined });
const результат3 = комнаты.застольеДляРейтинга(комната3);
проверить('человек имеет переводной: false (не true, не undefined)', результат3[0].переводной === false);
проверить('бот имеет переводной: false (не true, не undefined)', результат3[1].переводной === false);

/**
 * ТЕСТ 4: проверяем, что парами тоже правильно работает
 */
console.log('\nТест 4: комната.парами = true');
const комната4 = создатьМокКомнату({ парами: true, переводной: true });
const результат4 = комнаты.застольеДляРейтинга(комната4);
проверить('человек имеет парами: true', результат4[0].парами === true);
проверить('человек имеет переводной: true', результат4[0].переводной === true);

/**
 * ТЕСТ 5: проверяем другие поля
 */
console.log('\nТест 5: другие поля сохраняются правильно');
const комната5 = создатьМокКомнату({ переводной: true });
const результат5 = комнаты.застольеДляРейтинга(комната5);
проверить('человек имеет номер телеграма', результат5[0].номер === 12345);
проверить('человек имеет имя', результат5[0].имя === 'Игрок 0');
проверить('человек не бот', результат5[0].этоБот === false);
проверить('человек победил (не в проигравших)', результат5[0].победил === true);
проверить('человек в ничьей нет', результат5[0].ничья === false);
проверить('бот проиграл', результат5[1].победил === false);

console.log('\n' + '='.repeat(60));
console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
if (провалов > 0) {
  process.exit(1);
}
