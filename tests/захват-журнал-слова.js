// Проверка Р15/Р20: слова журнала раскрытия «Захвата» — без жаргона, с родом и числом, строка «Вы: …» не длиннее 36 знаков.
// Запуск:  node tests/захват-журнал-слова.js            — обычный прогон (без браузера)
//          node tests/захват-журнал-слова.js --сломать  — портит КОПИИ js/захват-раскрытие.js во временной папке, требует провала
// Довод --файл <путь> — проверить другой (порченый) захват-раскрытие.js; рядом должны лежать захват-карты.js и захват-правила.js.
// Что держим: нулевая часть потерь не пишется; «взять не удалось» вместо «отбит»; «вернулось/вернулись» по числу;
// «Вы: …» ≤ 36 знаков, в том числе при двузначных числах областей и войск; вокруг тире в строках журнала нет кавычек.
'use strict';
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const а = process.argv.slice(2);
const довод = (имя) => { const и = а.indexOf(имя); return и === -1 ? null : а[и + 1]; };
const путьФайла = довод('--файл') || path.join(КОРЕНЬ, 'js', 'захват-раскрытие.js');

if (а.includes('--сломать')) сломать();
else process.exit(прогон());

function прогон() {
  const Р = require(path.resolve(путьФайла));
  let провалов = 0, всего = 0;
  const всеСтроки = [];   // всё, что выдали журнал и итог: для общих проверок слов в конце
  function ждать(строка, образец, имя) {
    всего++;
    if (строка !== образец) { провалов++; console.log('ПРОВАЛ — ' + имя + ': вышло «' + строка + '»'); }
  }
  function нужно(условие, имя) {
    всего++;
    if (!условие) { провалов++; console.log('ПРОВАЛ — ' + имя); }
  }
  function журнал(с, я) {
    const р = Р.построить({ события: [с], раунд: 1, карта: 'материк', имена: { 'Бот 1': 'Бот 1', 'Бот 2': 'Бот 2', Вася: 'Вася' }, я: я || null });
    нужно(р.журнал.length > 0, 'журнал не пуст (ноль найденного — провал)');
    if (!р.журнал.length) return '';
    р.журнал.forEach((с2) => всеСтроки.push(с2));
    return р.журнал[0];
  }
  const уд = { вид: 'удар', откуда: [{ область: 5, сколько: 5 }], выстрелыНападающих: [], выстрелыЗащитников: [], домой: 0, столица: false, кто: 'Бот 1', куда: 10, сколько: 5, защитников: 3, у: 'Бот 2', исход: 'отбит', выбитоНападающих: 2, выбитоЗащитников: 3, осталось: 1 };
  ждать(журнал(уд), 'Удар Бота 1 → Брод (у Бота 2): 5 против 3 — взять не удалось. Погибло: у Бота 1 — 2, у Бота 2 — 3', 'удар не взят');
  ждать(журнал(Object.assign({}, уд, { выбитоНападающих: 0 })), 'Удар Бота 1 → Брод (у Бота 2): 5 против 3 — взять не удалось. Погибло: у Бота 2 — 3', 'нулевая часть не пишется');
  ждать(журнал(Object.assign({}, уд, { выбитоНападающих: 0, выбитоЗащитников: 0 })), 'Удар Бота 1 → Брод (у Бота 2): 5 против 3 — взять не удалось. Погибших нет', 'обе нулевые');
  ждать(журнал(Object.assign({}, уд, { у: null })), 'Удар Бота 1 → Брод (без хозяина): 5 против 3 — взять не удалось. Погибло: у Бота 1 — 2, у защитников — 3', 'защитники без хозяина');
  ждать(журнал(Object.assign({}, уд, { исход: 'погибли' })).replace(/ — .*/, ''), 'Удар Бота 1 → Брод (у Бота 2): 5 против 3', 'все нападавшие: голова');
  const пог = Object.assign({}, уд, { исход: 'погибли', осталось: 0 });
  ждать(журнал(пог), 'Удар Бота 1 → Брод (у Бота 2): 5 против 3 — все нападавшие погибли, хозяин прежний', 'все погибли');
  ждать(журнал(Object.assign({}, пог, { у: null })), 'Удар Бота 1 → Брод (без хозяина): 5 против 3 — все нападавшие погибли, хозяина нет', 'все погибли, без хозяина');
  ждать(журнал(Object.assign({}, уд, { кто: 'Вася', у: 'Бот 2' }), 'Вася'), 'Ваш удар → Брод (у Бота 2): 5 против 3 — взять не удалось. Погибло: у вас — 2, у Бота 2 — 3', 'свой удар');
  ждать(журнал(Object.assign({}, уд, { у: 'Вася' }), 'Вася'), 'Удар Бота 1 → Брод (у вас): 5 против 3 — взять не удалось. Погибло: у Бота 1 — 2, у вас — 3', 'удар по вам');
  const встр = (исход, ост) => ({ вид: 'встречный', области: [10, 11], исход: исход, обмены: [], колонны: [{ кто: 'Бот 1', было: 5, осталось: ост[0] }, { кто: 'Бот 2', было: 4, осталось: ост[1] }] });
  ждать(журнал(встр('разошлись', [2, 1])), 'Колонны встретились в пути (Брод и Мельница): у Бота 1 из 5 осталось 2, у Бота 2 из 4 — 1 — уцелевшие пошли дальше', 'встречный разошлись');
  ждать(журнал(встр('обе погибли', [0, 0])), 'Колонны встретились в пути (Брод и Мельница): у Бота 1 из 5 осталось 0, у Бота 2 из 4 — 0 — погибли все', 'встречный обе погибли');
  const рас = (кто, сколько, куда, у) => ({ вид: 'рассеялись', кто: кто, куда: куда, сколько: сколько, у: у });
  ждать(журнал(рас('Вася', 3, 10, 'Бот 1'), 'Вася'), 'Ваши 3 войска вернулись, а Брод уже не ваш — эти войска пропали', 'рассеялись, вы');
  ждать(журнал(рас('Бот 1', 3, 10, 'Бот 2')), '3 войска Бота 1 вернулись, а Брод уже не за Ботом 1 — эти войска пропали', 'рассеялись, чужие');
  ждать(журнал(рас('Бот 1', 3, 10, null)), '3 войска Бота 1 вернулись, а Брод без хозяина — эти войска пропали', 'рассеялись, без хозяина');
  ждать(журнал(рас('Вася', 1, 11, 'Бот 1'), 'Вася'), 'Ваше 1 войско вернулось, а Мельница уже не ваша — это войско пропало', 'одно войско');

  // «Вы: удар не взял область» — строка итога про игрока.
  const итог = Р.построить({ события: [Object.assign({}, уд, { кто: 'Вася' })], раунд: 1, карта: 'материк', имена: {}, я: 'Вася' }).итог;
  итог.forEach((с) => всеСтроки.push(с));
  нужно(итог.length > 0 && итог[0] === 'Вы: не взяли, погибло 2 войска', 'итог — «Вы: не взяли, погибло 2 войска»: ' + итог.join('|'));

  // Первая строка итога про вас — не длиннее 36 знаков, в том числе при двузначных областях и войсках.
  function первая(события) {
    const р = Р.построить({ события: события, раунд: 1, карта: 'материк', имена: { 'Бот 1': 'Бот 1', Вася: 'Вася' }, я: 'Вася' });
    нужно(р.итог.length > 0, 'итог не пуст (ноль найденного — провал)');
    if (!р.итог.length) return '';
    р.итог.forEach((с) => всеСтроки.push(с));
    р.журнал.forEach((с) => всеСтроки.push(с));
    return р.итог[0];
  }
  const мойУдар = (добавка) => Object.assign({}, уд, { кто: 'Вася', у: 'Бот 1' }, добавка);
  const чужойУдар = (добавка) => Object.assign({}, уд, { кто: 'Бот 1', у: 'Вася' }, добавка);
  // Серия взятий: n областей подряд, номера областей разные.
  const взятия = (n, кто, у, начало) => {
    const список = [];
    for (let и = 0; и < n; и++) список.push(Object.assign({}, уд, { кто: кто, у: у, куда: начало + и, исход: 'взята', осталось: 5, выбитоНападающих: 0, выбитоЗащитников: 0 }));
    return список;
  };
  const варианты = [
    [мойУдар({ выбитоНападающих: 99 })],
    [чужойУдар({ выбитоЗащитников: 99 })],
    [мойУдар({ выбитоНападающих: 55 }), чужойУдар({ выбитоЗащитников: 44 })],
    [мойУдар({ выбитоНападающих: 99, исход: 'погибли', осталось: 0 })],
    [мойУдар({ исход: 'взята', осталось: 5, выбитоНападающих: 99 })],
    [мойУдар({ исход: 'взята', осталось: 5, выбитоНападающих: 99 }), мойУдар({ куда: 11, исход: 'взята', осталось: 5 })],
    [чужойУдар({ исход: 'взята', осталось: 5, выбитоЗащитников: 99 }), чужойУдар({ куда: 11, исход: 'взята', осталось: 5 })],
    [мойУдар({ выбитоНападающих: 99 }), { вид: 'рассеялись', кто: 'Вася', куда: 10, сколько: 99, у: 'Бот 1' }],
    // Двузначные области: взято 12, потеряно 11, погибло 99 — самая длинная строка.
    взятия(12, 'Вася', 'Бот 1', 1).concat(взятия(11, 'Бот 1', 'Вася', 20), [мойУдар({ куда: 40, выбитоНападающих: 99 })]),
    взятия(12, 'Вася', 'Бот 1', 1).concat([мойУдар({ куда: 40, выбитоНападающих: 99 })]),
    взятия(11, 'Бот 1', 'Вася', 20).concat([чужойУдар({ куда: 40, выбитоЗащитников: 99 })]),
    взятия(12, 'Вася', 'Бот 1', 1).concat(взятия(11, 'Бот 1', 'Вася', 20))
  ];
  варианты.forEach((в, и) => {
    const строка = первая(в);
    нужно(строка.length <= 36, 'вариант ' + и + ' не длиннее 36 (' + строка.length + '): «' + строка + '»');
    нужно(/^Вы/.test(строка), 'вариант ' + и + ' начинается с «Вы» (ноль найденного — провал): «' + строка + '»');
  });
  // Самый длинный вариант: чтобы проверка не была пустой, убеждаемся, что двузначные числа в строку вообще попали.
  const длинная = первая(варианты[8]);
  нужно(/\d\d/.test(длинная), 'в самой длинной строке есть двузначное число: «' + длинная + '»');
  ждать(первая(варианты[0]), 'Вы: не взяли, погибло 99 войск', 'длинный вариант');

  // Жаргона в текстах журнала быть не должно.
  const все = всеСтроки.join('\n');
  нужно(/Удар Бота 1/.test(все), 'в общем списке строк есть журнал (ноль найденного — провал)');
  нужно(!/отбит|рассеял|разошлись|не нашл/.test(все.replace(/хозяин прежний/g, '')), 'в журнале нет жаргона: ' + все.split('\n').filter((с) => /отбит|рассеял|разошлись|не нашл/.test(с))[0]);
  // Тире — просто тире: вокруг него в строках журнала нет кавычек («—», "—", '—').
  const сКавычками = всеСтроки.filter((с) => /["'«“„‘]\s*[—–-]\s*["'»”“’]/.test(с));
  нужно(сКавычками.length === 0, 'вокруг тире нет кавычек: «' + (сКавычками[0] || '') + '»');
  нужно(всеСтроки.some((с) => с.indexOf(' — ') !== -1), 'в журнале тире вообще есть (ноль найденного — провал)');

  console.log('Итого проверок: ' + всего + ', провалов: ' + провалов);
  return провалов ? 1 : 0;
}

function сломать() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-журнал-слова-'));
  const исходник = fs.readFileSync(path.join(КОРЕНЬ, 'js', 'захват-раскрытие.js'), 'utf8');
  const порчи = [
    ['итог снова длинный: «удар не взял область»', "части.push('не взяли')", "части.push('удар не взял область')"],
    ['нулевая часть пишется', "части.push('у ' + кого(к, с.кто) + ' — ' + с.выбитоНападающих);", "части.push('у ' + кого(к, с.кто) + ' — ' + с.выбитоНападающих);\n    if (true) части.push('у ' + кого(к, с.кто) + ' — ' + 0);"],
    ['«вернулся» вместо «вернулось/вернулись»', "(одно ? ' вернулось, а ' : ' вернулись, а ')", "' вернулся, а '"],
    ['«отбит» вместо «взять не удалось»', "return голова + 'взять не удалось. ' + потериУдара(к, с);", "return голова + 'отбит. ' + потериУдара(к, с);"],
    ['у тире появились кавычки', "почему + ' — ' + (одно", "почему + ' «—» ' + (одно"],
    ['длинную строку итога не укорачивают', 'if (строка.length > 36 && потеряноОбластей > 0) {', 'if (false) {'],
    ['потери войск выросли вдвое', "потеряноВойск += с.выбитоНападающих;", "потеряноВойск += с.выбитоНападающих * 2;"],
    ['«Вы» вместо «Ваш удар»', "'Ваш удар'", "'Вы ударили'"]
  ];
  let красных = 0, ненайдено = 0;
  порчи.forEach(function (п, н) {
    if (исходник.split(п[1]).length !== 2) { ненайдено++; console.log('ПРОВАЛ — место порчи не найдено ровно один раз: ' + п[0]); return; }
    const под = path.join(папка, 'п' + н);
    fs.mkdirSync(под);
    for (const ф of ['захват-правила.js', 'захват-карты.js']) fs.copyFileSync(path.join(КОРЕНЬ, 'js', ф), path.join(под, ф));
    const путь = path.join(под, 'захват-раскрытие.js');
    fs.writeFileSync(путь, исходник.replace(п[1], () => п[2]));
    const р = spawnSync(process.execPath, [__filename, '--файл', путь], { encoding: 'utf8' });
    const красная = р.status === 1 && /ПРОВАЛ/.test(р.stdout);
    if (красная) красных++;
    console.log((красная ? 'КРАСНЕЕТ' : 'НЕ КРАСНЕЕТ (плохо)') + ' — ' + п[0] + ' (код ' + р.status + ')');
  });
  const чист = spawnSync(process.execPath, [__filename], { encoding: 'utf8' });
  console.log('Обычный прогон: код ' + чист.status + ' — ' + чист.stdout.trim().split('\n').pop());
  console.log('Красных: ' + красных + ' из ' + порчи.length);
  process.exit(красных === порчи.length && чист.status === 0 ? 0 : 1);
}
