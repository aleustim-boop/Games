'use strict';

/* =====================================================================
   СТРАЖ: КОСТИ В НАРДАХ БРОСАЕТ NODE:CRYPTO, А НЕ MATH.RANDOM

   Что проверяем. В server/игры/нарды.js есть функция «кость» (около
   строки 89) — она и есть бросок одной кости. Кубики со стороны браузера
   сервер не принимает никогда («клиенту не верим»), поэтому важно, чтобы
   само число бралось из настоящей случайности node:crypto (randomInt),
   а не из Math.random — тот предсказуем по паре подсмотренных чисел, и
   в бою кубиков это дыра для читера.

   Как проверяем.
     1) СТРАЖ ПО ИСХОДНИКУ (всегда): читаем текст файла, находим тело
        функции «кость», смотрим, что в файле подключён node:crypto (или
        crypto), в теле функции есть randomInt и нет Math.random.
        Не нашли функцию «кость» вовсе — это провал, а не пропуск: значит
        либо её переименовали, либо страж ищет не то.
     2) ПОВЕДЕНИЕ (только когда путь не передан, то есть проверяем файл
        проекта, а не ломающую копию): бросок «кость()» наружу отдельной
        функцией не экспортирован, но доступен ОКОЛЬНЫМ путём — через
        дверь «/ход» с действием «бросить»: раздаём партию, один раз
        бросаем и читаем выпавшее через видДляИгрока().бросок. Так делаем
        200 раз (каждый раз заново раздавая партию, чтобы можно было
        бросать без доигрывания хода) и проверяем: все значения от 1 до 6,
        и хотя бы 4 разных значения встретились — иначе кубики не похожи
        на случайные.

   Запуск (файл проекта):
     node tests/нарды-кости-из-crypto.js

   Ломающий запуск (копия с Math.random вместо randomInt должна
   покраснеть на страже по исходнику; поведение на ломающей копии не
   проверяется — копия лежит без соседей и не грузится require'ом):
     node tests/нарды-кости-из-crypto.js ПУТЬ_К_ИСПОРЧЕННОЙ_КОПИИ
   ===================================================================== */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ПУТЬ_ПО_УМОЛЧАНИЮ = path.join(КОРЕНЬ, 'server', 'игры', 'нарды.js');
const путьДовод = process.argv[2];
const ПУТЬ = путьДовод ? path.resolve(путьДовод) : ПУТЬ_ПО_УМОЛЧАНИЮ;
const этоЛомающийЗапуск = Boolean(путьДовод);

let ошибок = 0;
let проверок = 0;

function шаг(ок, текст) {
  проверок++;
  if (!ок) ошибок++;
  console.log((ок ? 'ок' : 'ПЛОХО') + ' — ' + текст);
}

console.log('=== Страж: кости нард берутся из node:crypto ===');
console.log('Файл: ' + ПУТЬ + (этоЛомающийЗапуск ? ' (ломающий запуск, копия)' : ' (файл проекта)'));
console.log('');

if (!fs.existsSync(ПУТЬ)) {
  console.log('ПЛОХО — файл не найден вовсе: ' + ПУТЬ);
  console.log('');
  console.log('Итого проверок: 1, провалов: 1');
  process.exit(1);
}

const текст = fs.readFileSync(ПУТЬ, 'utf8');

/* Тело функции «кость». Она однострочная (никаких вложенных фигурных
   скобок внутри), поэтому простого «до первой закрывающей скобки»
   достаточно и не нужен парсер JS. */
const совпадениеФункции = текст.match(/function\s+кость\s*\(\s*\)\s*\{([^}]*)\}/);
шаг(Boolean(совпадениеФункции), 'функция «кость» нашлась в файле (иначе непонятно, что вообще проверять)');

if (!совпадениеФункции) {
  console.log('');
  console.log('Итого проверок: ' + проверок + ', провалов: ' + ошибок);
  process.exit(1);
}

const телоФункции = совпадениеФункции[1];

const подключаетCrypto = /require\(\s*['"](?:node:)?crypto['"]\s*\)/.test(текст);
шаг(подключаетCrypto, 'файл подключает node:crypto (или crypto) хоть где-то');

const естьRandomInt = /randomInt/.test(телоФункции);
шаг(естьRandomInt, 'в теле функции «кость» есть randomInt');

const нетMathRandom = !/Math\.random/.test(телоФункции);
шаг(нетMathRandom, 'в теле функции «кость» нет Math.random');

/* Поведенческую часть гоняем только на настоящем файле проекта: ломающая
   копия физически лежит без соседних require'ов (../../игры/нарды/нарды-правила.js
   и так далее) и корректно не подключится — это ожидаемо, не баг. */
if (!этоЛомающийЗапуск) {
  console.log('');
  console.log('--- Поведение: 200 бросков через настоящую дверь «/ход' + "'" + ' действие «бросить» ---');
  try {
    const нарды = require(ПУТЬ);
    const ВСЕГО_БРОСКОВ = 200;
    const встреченныеЗначения = new Set();
    let всеВДиапазоне = true;
    let сколькоПринято = 0;

    for (let i = 0; i < ВСЕГО_БРОСКОВ; i++) {
      const партия = нарды.раздать('a', { игроки: ['a', 'b'] });
      const ответ = нарды.сделатьХод(партия, 'a', { действие: 'бросить' });
      if (!ответ.принято) continue; // считаем ниже отдельно, в норме такого не бывает
      сколькоПринято++;
      const вид = нарды.видДляИгрока(партия, 'a', {});
      const бросок = вид.бросок || [];
      for (const значение of бросок) {
        встреченныеЗначения.add(значение);
        if (!(Number.isInteger(значение) && значение >= 1 && значение <= 6)) {
          всеВДиапазоне = false;
        }
      }
    }

    шаг(сколькоПринято === ВСЕГО_БРОСКОВ, 'все ' + ВСЕГО_БРОСКОВ + ' бросков приняты сервером (получилось: ' + сколькоПринято + ')');
    шаг(всеВДиапазоне, 'каждое выпавшее значение — целое число от 1 до 6');
    шаг(встреченныеЗначения.size >= 4, 'за ' + ВСЕГО_БРОСКОВ + ' бросков встретилось хотя бы 4 разных значения (получилось: ' + встреченныеЗначения.size + ' — ' + Array.from(встреченныеЗначения).sort().join(',') + ')');
  } catch (ошибка) {
    шаг(false, 'модуль нард подключился и отработал 200 бросков без ошибки (поймано: ' + ошибка.message + ')');
  }
} else {
  console.log('');
  console.log('(поведение на ломающей копии не проверяется — см. пояснение в шапке файла)');
}

console.log('');
console.log('Итого проверок: ' + проверок + ', провалов: ' + ошибок);
process.exit(ошибок ? 1 : 0);
