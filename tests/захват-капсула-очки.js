function р24() {
  const экран = fs.readFileSync(путьЭкрана, 'utf8');
  const страница = fs.readFileSync(путьСтраницы, 'utf8');
  const совет = /(?:^|\\s)очки:\\s*'([^']*)'/.exec(экран);
  проверка('Р24: в экране найден СОВЕТЫ.очки (ноль — провал)', !!совет);
  if (совет) {
    проверка('Р24: подсказка — «Очки дают области: 1 за область, 3 за столицу. Очки — у имени игрока»',
      совет[1] === 'Очки дают области: 1 за область, 3 за столицу. Очки — у имени игрока', совет[1]);
    проверка('Р24: подсказка не длиннее 85 знаков', совет[1].length <= 85, совет[1].length + ' знаков');
    проверка('Р24: в подсказке нет сокращений «обл» и «оч»', !/(^|[^а-яё])обл([^а-яё]|$)/i.test(совет[1]) && !/(^|[^а-яё])оч([^а-яё]|$)/i.test(совет[1]), совет[1]);
  }
  проверка('Р24: в экране нет старой подсказки «У имени: обл — области, оч — очки»', !/У имени: обл/.test(экран));
  проверка('Р24: в справке «Встреча в пути»', страница.indexOf('В итоге раунда это «Встреча в пути»') !== -1);
  проверка('Р24: в справке «Счёт у имени» с «31 очко»', страница.indexOf('<strong>Счёт у имени.</strong> «31 очко» — очки игрока: 1 за область, 3 за столицу. «ведёт» — у кого очков больше всех.') !== -1);
  проверка('Р24: в справке нет «N обл · M оч»', !/обл ·/.test(страница) && !/ оч[»\\s.,<]/.test(страница), 'найдено старое сокращение');
}

