/* ---------------------------------------------------------------------
   Подпись Telegram — по тому же правилу, что у сервера.
   --------------------------------------------------------------------- */

function подписать(поля) {
  const строки = Object.keys(поля)
    .filter(function (к) { return к !== 'hash'; })
    .map(function (к) { return к + '=' + поля[к]; })
    .sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(ТОКЕН_ДЛЯ_ПРОБЫ).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}

function подписьИгрока(номер, имя) {
  const поля = {
    query_id: 'AAF' + номер,
    user: JSON.stringify({ id: номер, first_name: имя, username: 'igrok' + номер }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  const сподписью = Object.assign({}, поля, { hash: подписать(поля) });
  return Object.keys(сподписью)
    .map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(сподписью[к]); })
    .join('&');
}

/* ---------------------------------------------------------------------
   Разговор с дверью
   --------------------------------------------------------------------- */

function спросить(путь, тело) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН_АДРЕС, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (сбой) { разобрано = null; }
        готово({ код: ответ.statusCode, тело: разобрано, текст: текст });
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

function дверь(путь, кто, имя, довесок) {
  const тело = Object.assign({ initData: подписьИгрока(кто, имя) }, довесок || {});
  return спросить(путь, тело);
}

/* ---------------------------------------------------------------------
   Настоящие столы для зовущих — /позвать сверяет и код, и что зовущий
   правда сидит за этим столом. Один игрок — один стол, храним пропуск,
   чтобы «трогать» комнату дверью /состояние.
   --------------------------------------------------------------------- */

const столыИгроков = new Map();   // кто → { код, пропуск }

async function стол(кто, имя) {
  if (столыИгроков.has(кто)) return столыИгроков.get(кто);
  const ответ = await дверь('/создать', кто, имя);
  const запись = {
    код: (ответ.тело && ответ.тело.код) || '',
    пропуск: (ответ.тело && ответ.тело.пропуск) || ''
  };
  столыИгроков.set(кто, запись);
  return запись;
}

/** Позвать по ключу от имени этого игрока, с его настоящего стола. */
async function позвать(кто, имя, ключ) {
  const мойСтол = await стол(кто, имя);
  const ссылка = ссылкаЗаСтол(мойСтол.код);
  return дверь('/позвать', кто, имя, { ключ: ключ, ссылка: ссылка, код: мойСтол.код });
}

/* ---------------------------------------------------------------------
   Подмена времени. Сервер живёт в этом же процессе и считает «сейчас»
   через голый Date.now() — подмена действует ровно на миг обработки
   запроса (весь путь запрос-ответ синхронен внутри await), сразу после
   возвращаем настоящее время. Заодно, ДО самого зова, трогаем свой стол
   дверью /состояние тем же поддельным временем — иначе TTL пустой
   комнаты (5 минут без касаний, server/комнаты.js) состарит стол раньше,
   чем должен сработать проверяемый предел зова.
   --------------------------------------------------------------------- */

const ДАТА_НАСТОЯЩАЯ = Date.now;

async function подВремя(время, действие) {
  Date.now = function () { return время; };
  try {
    return await действие();
  } finally {
    Date.now = ДАТА_НАСТОЯЩАЯ;
  }
}

/** Тронуть стол (обновить «трогали» комнаты) и тут же позвать — оба шага
    под одним и тем же поддельным временем. */
async function тронутьИПозвать(время, кто, имя, ключ) {
  return подВремя(время, async function () {
    const мойСтол = await стол(кто, имя);
    await спросить('/состояние', { код: мойСтол.код, пропуск: мойСтол.пропуск });
    return позвать(кто, имя, ключ);
  });
}

