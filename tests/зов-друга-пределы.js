/* =====================================================================
   ПРЕДЕЛЫ ЗОВА ДРУГА (без общей партии): часто ли можно звать.

   Что проверяем. Дверь POST /позвать зовёт письмом не только ЗНАКОМОГО
   (с кем правда играли), но и просто ДРУГА — взаимного, без единой
   партии между ними (server/сервер.js, найтиАдресатаЗова). Сам факт
   такого зова уже проверен в tests/зов-друга-и-скрытность.js. Здесь —
   отдельно и дотошно три предела, которые должны сдерживать зов ДРУГА
   ровно так же, как сдерживают зов знакомого (server/сервер.js,
   почемуЗватьРано):
     1. один и тот же зовущий — не больше 5 зовов в час (ЗОВОВ_В_ЧАС);
        шестой (другому другу) обязан быть отказан;
     2. одного и того же друга — не чаще раза в 5 минут
        (ЗВАТЬ_ТОГО_ЖЕ_НЕ_ЧАЩЕ); повторный зов раньше срока отказан,
        зов после 5 минут — снова проходит;
     3. другу, который попросил «не звать меня» (неЗвать.запретить),
        зов отказан, даже если дружба взаимная и честная.

   Чем это опасно, если сломано. Без часового предела один человек может
   разослать письма от имени бота хоть всему списку друзей за минуту.
   Без минутного предела на одного и того же — можно превратить кнопку
   зова в стук в закрытую дверь. Без уважения к «не звать меня» отказ
   человека ничего не значит.

   Как испытываем время. Сервер требует друзей и правила зова из ЭТОГО ЖЕ
   процесса (в памяти, никакой сети наружу), и внутри своих функций
   считает время через голый Date.now() — не через сохранённую ссылку.
   Значит время можно подменить: на миг запроса подменяем Date.now() на
   нужное число, шлём запрос дверям /состояние и /позвать (обработка
   идёт синхронно в этом же процессе, до того как наш http-ответ придёт),
   и сразу возвращаем настоящее время назад. Так пять зовов за час и
   контрольный шестой проверяются без единой секунды настоящего ожидания.

   Обязательный побочный шаг — «трогать» свой стол перед каждым шагом
   времени дверью /состояние (код+пропуск, без Telegram): у КОМНАТЫ, где
   ещё не играли, есть свой предел жизни без касаний (ЖИЗНЬ_ПУСТОЙ_КОМНАТЫ,
   server/комнаты.js, 5 минут). Если не трогать стол, скачок виртуального
   времени вперёд состарит стол раньше, чем предел зова успеет сработать,
   и /позвать откажет по «стол не найден» — не по тому пределу, который
   мы хотим проверить. Трогаем стол на КАЖДОМ шаге, поэтому между
   касаниями всегда меньше 5 минут — стол живёт всё время проверки.

   Настоящего Telegram здесь нет: сервер отдаёт наружу щель для проверок
   (оснасткаДляПроверки) — выдуманный токен и поддельная труба вместо
   api.telegram.org. Данные уведены в свою временную папку и стираются
   по выходу процесса. Боевые порты (8790/8765) не трогаем — свой сервер
   слушает отдельный порт.

   Запуск:
       node tests/зов-друга-пределы.js
       node tests/зов-друга-пределы.js 8803       (свой порт)
       node tests/зов-друга-пределы.js --корень=ПУТЬ (своя копия проекта:
                                                       ищет ПУТЬ/server/сервер.js)

   Ломающий прогон (проверка обязана покраснеть) — доводом «--корень=ПУТЬ»
   на нарочно испорченную КОПИЮ папки server/ (сама проверка ничего не
   портит — портит тот, кто ломает, и только копию во временной папке,
   не файлы проекта):
     в server/сервер.js поднять предел «const ЗОВОВ_В_ЧАС = 5;» до
     какого-нибудь большого числа (например 50) — пункт 1 обязан
     провалиться: шестой зов, который должен быть отказан часовым
     пределом, на испорченной копии тихо пройдёт (ок: true).

   Ноль найденного — тоже провал: если предел не сработал там, где
   обязан, — это красная проверка, а не «нечего проверять».

   Выход 0 — провалов нет, 1 — есть.
   ===================================================================== */

