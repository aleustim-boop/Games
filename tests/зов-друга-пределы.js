/** Тело function ИМЯ(...) {...} как обычный текст (для поиска внутри). */
function телоФункции(текст, имя) {
  const метка = 'function ' + имя + '(';
  const начало = текст.indexOf(метка);
  if (начало === -1) throw new Error('в ' + ПУТЬ_СЕРВЕРА + ' не нашлась функция ' + имя);
  const закрывающая = текст.indexOf(')', начало);
  const телоНачало = текст.indexOf('{', закрывающая);
  let глубина = 0, конец = телоНачало;
  for (; конец < текст.length; конец++) {
    if (текст[конец] === '{') глубина++;
    else if (текст[конец] === '}') { глубина--; if (глубина === 0) break; }
  }
  return текст.slice(телоНачало + 1, конец);
}

/** Значение const ИМЯ = 'лит1' + 'лит2' + ...; — как оно записано в файле
    (только чистая конкатенация строк, без переменных внутри). */
function константаСервера(имя) {
  const рег = new RegExp('const\\s+' + имя + '\\s*=\\s*((?:\'(?:[^\'\\\\]|\\\\.)*\'\\s*\\+?\\s*)+);');
  const совпадение = ТЕКСТ_СЕРВЕРА.match(рег);
  if (!совпадение) throw new Error('в ' + ПУТЬ_СЕРВЕРА + ' не нашлась константа ' + имя);
  const литералы = совпадение[1].match(/'(?:[^'\\]|\\.)*'/g) || [];
  return литералы.map(function (л) { return л.slice(1, -1); }).join('');
}

/** return 'ТОЧНЫЙ ОДИНОЧНЫЙ ЛИТЕРАЛ'; внутри тела функции — как записано.
    Годится только для return без конкатенации (переменных внутри нет). */
function точныйВозвратВФункции(имяФункции) {
  const тело = телоФункции(ТЕКСТ_СЕРВЕРА, имяФункции);
  const рег = /return\s+'((?:[^'\\]|\\.)*)'\s*;/g;
  const найдено = [];
  let м;
  while ((м = рег.exec(тело))) найдено.push(м[1]);
  return найдено;
}

