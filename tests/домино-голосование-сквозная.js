/** Кто сверху в середине узла: 'ок' или что лежит поверх. */
function сверхуУзла(сел) {
  const у = document.querySelector(сел);
  if (!у) return 'нет узла ' + сел;
  const р = у.getBoundingClientRect();
  if (!(р.width > 0 && р.height > 0)) return 'у узла нулевой размер';
  const x = р.left + р.width / 2, y = р.top + р.height / 2;
  if (x < 0 || y < 0 || x > window.innerWidth || y > window.innerHeight) return 'центр узла за краем экрана';
  const ц = document.elementFromPoint(x, y);
  if (ц && (ц === у || у.contains(ц))) return 'ок';
  return 'сверху лежит ' + (ц ? ц.tagName + (ц.id ? '#' + ц.id : '') + (ц.className && typeof ц.className === 'string' ? '.' + ц.className : '') : 'ничего');
}
