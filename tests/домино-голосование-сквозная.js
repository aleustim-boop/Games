/** Довести раунд до итога (или конца партии) ходами сервера. Отдаёт фазу. */
function довестиДоИтога() {
  for (let k = 0; k < 600; k++) {
    const п = партия();
    if (п.игра.фаза === 'итог' || п.игра.фаза === 'конец' || п.завершена) return п.игра.фаза;
    const р = серверныйХод(Д.чейХод(п));
    if (!р.принято) throw ошибка('сервер не принял ход бота-помощника: ' + р.причина);
  }
  throw ошибка('за 600 ходов раунд не кончился');
}
