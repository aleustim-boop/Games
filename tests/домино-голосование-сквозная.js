const ТИПЫ = { '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp',
  '.svg': 'image/svg+xml', '.woff2': 'font/woff2', '.woff': 'font/woff', '.mp3': 'audio/mpeg', '.ico': 'image/x-icon' };
function поднятьСерверФайлов() {
  const с = http.createServer(function (запрос, ответ) {
    let путь;
    try { путь = decodeURIComponent(new URL(запрос.url, 'http://x').pathname); } catch (_) { ответ.writeHead(400); ответ.end(); return; }
    const файл = путь === '/' ? path.join(ПРОЕКТ, 'index.html') : path.join(ПРОЕКТ, путь);
    if (path.relative(ПРОЕКТ, файл).startsWith('..')) { ответ.writeHead(403); ответ.end(); return; }
    const отн = path.relative(ПРОЕКТ, файл).split(path.sep).join('/');
    const отдать = ФАЙЛ_ЭКРАНА && отн === ИМЯ_ЭКРАНА ? ФАЙЛ_ЭКРАНА : файл;
    fs.readFile(отдать, function (ош, данные) {
      if (ош) { ответ.writeHead(404); ответ.end('нет файла'); return; }
      ответ.writeHead(200, { 'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'application/octet-stream', 'Cache-Control': 'no-store' });
      ответ.end(данные);
    });
  });
  return new Promise((готово, беда) => { с.once('error', беда); с.listen(0, '127.0.0.1', () => готово(с)); });
}

