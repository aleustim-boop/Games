/* ---------------------------------------------------------------------
   Копия server/ + js/ во временную папку — «портим» и требуем только
   там (тот же приём, что в tests/возврат-за-стол.js и
   tests/рейтинг-круг-друзей-сервер.js).
   --------------------------------------------------------------------- */
function подготовитьРабочуюКопию() {
  const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'фото-по-сети-'));
  const ПАПКА_ДАННЫХ = path.join(КОРЕНЬ, 'server', 'данные');
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(врем, 'server'), {
    recursive: true,
    // Настоящие данные игроков этому прогону не нужны и не должны в него попасть.
    filter: function (откуда) { return откуда !== ПАПКА_ДАННЫХ && !откуда.startsWith(ПАПКА_ДАННЫХ + path.sep); }
  });
  fs.cpSync(path.join(КОРЕНЬ, 'js'), path.join(врем, 'js'), { recursive: true });
  return врем;
}

