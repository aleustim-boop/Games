function запросJSON(порт, путь, тело) {
  return new Promise(function (готово) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const req = http.request({
      host: ХОСТ, port: порт, method: 'POST', path: encodeURI(путь),
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let куски = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (к) { куски += к; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(куски); } catch (е) { разобрано = { разбор: 'не JSON', сырое: куски }; }
        готово({ статус: ответ.statusCode, данные: разобрано, текст: куски });
      });
    });
    req.on('error', function (е) { готово({ статус: 0, данные: { ошибка: String(е.message) }, текст: '' }); });
    req.write(данные);
    req.end();
  });
}

/** GET по буквальному пути: структуру (слэши, точки — в т.ч. «..») не
 *  трогаем вовсе, только encodeURI спасает от отказа http.request на
 *  не-ASCII байтах (кириллица в мусорных ключах). encodeURI НЕ схлопывает
 *  «..» и не нормализует путь — в отличие от new URL(...).pathname,
 *  которым пользуется общий разбор адреса в сервере (потому здесь и
 *  нужен отдельный, «сырой» способ сходить по адресу). */
function запросGETСырой(порт, сыройПуть) {
  return new Promise(function (готово) {
    const req = http.request({ host: ХОСТ, port: порт, method: 'GET', path: encodeURI(сыройПуть) }, function (ответ) {
      const куски = [];
      ответ.on('data', function (к) { куски.push(к); });
      ответ.on('end', function () {
        готово({ статус: ответ.statusCode, заголовки: ответ.headers, тело: Buffer.concat(куски) });
      });
    });
    req.on('error', function (е) { готово({ статус: 0, заголовки: {}, тело: Buffer.alloc(0), ошибка: String(е.message) }); });
    req.end();
  });
}

function запросФото(порт, ключ) {
  return запросGETСырой(порт, '/фото/' + ключ);
}

function подписать(поля, токен) {
  const строки = Object.keys(поля)
    .filter(function (к) { return к !== 'hash'; })
    .map(function (к) { return к + '=' + поля[к]; })
    .sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(токен).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}

function initDataДля(номер, имя) {
  const поля = {
    query_id: 'AAFOTO' + номер,
    user: JSON.stringify({ id: номер, first_name: имя, username: 'игрок' + номер }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  const сподписью = Object.assign({}, поля, { hash: подписать(поля, ТОКЕН) });
  return Object.keys(сподписью)
    .map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(сподписью[к]); })
    .join('&');
}

function рейтингИгрока(порт, номер, имя) {
  return запросJSON(порт, '/рейтинг', { initData: initDataДля(номер, имя), игра: 'дурак' });
}

/* Ищем точное число как отдельный номер (границы \d, не \b — тест
   лишь на ASCII-цифрах, но так надёжнее и без сюрпризов). */
function номерВстречаетсяВТексте(текст, номер) {
  const рег = new RegExp('(^|[^0-9])' + String(номер) + '($|[^0-9])');
  return рег.test(текст);
}

