'use strict';

/* =====================================================================
   Выдерживает ли туннель «длинный опрос».

   Как игра узнаёт о ходе соперника: она отправляет вопрос «что нового?»
   и сервер НЕ отвечает сразу — держит соединение открытым до 25 секунд,
   пока новость не появится. Если Cloudflare между ними рвёт такие
   долгие соединения, второй игрок просто не увидит ход первого:
   партия будет выглядеть зависшей.

   Этот замер создаёт комнату и честно ждёт: сколько секунд туннель
   продержал соединение и чем ответил.

   Запуск:
       node tests/замер-длинного-опроса-через-туннель.js https://адрес
   ===================================================================== */

const https = require('https');
const http = require('http');
const { URL } = require('url');

const АДРЕС = (process.argv[2] || '').replace(/\/+$/, '');
const ПОВТОРОВ = Number(process.argv[3]) || 3;

if (!АДРЕС) {
  console.log('Скажите адрес сервера, например:');
  console.log('  node tests/замер-длинного-опроса-через-туннель.js https://пример.trycloudflare.com');
  process.exit(1);
}

function запрос(путь, тело, ждатьМс) {
  return new Promise(function (готово, беда) {
    const начало = Date.now();
    const цель = new URL(АДРЕС + encodeURI(путь));
    const транспорт = цель.protocol === 'https:' ? https : http;
    const текст = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const обращение = транспорт.request({
      protocol: цель.protocol, hostname: цель.hostname,
      port: цель.port || (цель.protocol === 'https:' ? 443 : 80),
      path: цель.pathname, method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Content-Length': текст.length,
        'Origin': 'https://aleustim-boop.github.io'
      }
    }, function (ответ) {
      let к = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (ч) { к += ч; });
      ответ.on('end', function () {
        let данные;
        try { данные = JSON.parse(к); }
        catch (сбой) { данные = { этоНеJSON: true, кусок: к.slice(0, 300) }; }
        готово({ номер: ответ.statusCode, данные: данные, секунд: (Date.now() - начало) / 1000 });
      });
    });
    обращение.setTimeout(ждатьМс || 60000, function () {
      обращение.destroy(new Error('ждали дольше ' + (ждатьМс / 1000) + ' с и не дождались'));
    });
    обращение.on('error', function (сбой) {
      сбой.секунд = (Date.now() - начало) / 1000;
      беда(сбой);
    });
    обращение.end(текст);
  });
}

(async function () {
  console.log('Сервер: ' + АДРЕС);
  const создание = await запрос('/создать', {});
  if (создание.номер !== 200 || !создание.данные.код) {
    console.log('Комнату создать не вышло: код ' + создание.номер);
    process.exit(1);
  }
  const код = создание.данные.код;
  const пропуск = создание.данные.пропуск;
  const версия = создание.данные.состояние.версия;
  console.log('Комната ' + код + ' создана. Теперь молчим и слушаем — ' +
    'новостей не будет, значит сервер должен держать соединение около 25 секунд.\n');

  let плохо = 0;
  for (let i = 1; i <= ПОВТОРОВ; i++) {
    try {
      const о = await запрос('/что-нового', { код: код, пропуск: пропуск, версия: версия }, 60000);
      const держал = о.секунд.toFixed(1);
      const норма = о.секунд >= 20;
      console.log('Опрос ' + i + ': держался ' + держал + ' с, ответ ' + о.номер +
        ', изменилось=' + о.данные.изменилось +
        (норма ? '  — туннель выдержал' : '  — ОБОРВАЛОСЬ РАНО, это поломка'));
      if (!норма) плохо++;
    } catch (сбой) {
      console.log('Опрос ' + i + ': СОРВАЛСЯ через ' +
        (сбой.секунд || 0).toFixed(1) + ' с — ' + сбой.message);
      плохо++;
    }
  }

  await запрос('/выйти', { код: код, пропуск: пропуск });
  console.log('\nИтог: ' + (плохо === 0
    ? 'туннель держит долгие соединения, игра вдвоём новости получит.'
    : 'туннель рвёт долгие соединения ' + плохо + ' раз из ' + ПОВТОРОВ +
      ' — второй игрок будет видеть зависшую партию.'));
  if (плохо) process.exitCode = 1;
})();
