/* =====================================================================
   ЧТО ИГРА ОТВЕЧАЕТ НА НАЖАТИЯ — и правду ли она отвечает.

   ЭТО НЕ АВТОПРОГОН ДЛЯ NODE. Файл вставляется в консоль браузера, когда
   игра уже открыта.

   ЗАЧЕМ. Игра научилась отвечать на каждое нажатие словами. Слова —
   дело хорошее ровно до тех пор, пока они правда. Проверенные здесь
   обещания игры (каждое когда-то оказывалось неправдой):

     1. «Зелёная черта — эту карту можно выбрать». Сказано — значит,
        хотя бы одна карта в руке с чертой быть обязана. Иначе игра
        отправляет человека искать то, чего нет: замер прошлого захода
        насчитал 149 показов подсказки, и в 70 из них черты не было
        ни на одной карте.
     2. «Ваше слово вернётся в следующем подходе» — сказано напарнику
        того, кто отбивается. Значит, слово и правда обязано вернуться.
     3. «Партия окончена — сейчас появится итог» — обещание на те
        секунду-две, пока плашки итога ещё нет. Раньше в этот миг
        нажатия не отвечали ничем.
     4. Вздрагивание карты на ВТОРОЙ быстрый тап. Раньше второй тап
        гасился таймером первого: пометка вспыхивала и пропадала.
     5. Отказ снимается, как только человек сделал законный ход.
     6. Промах мимо карты дважды подряд отвечает разными словами.

   Ни одна проверка не сверяет слова со списком, переписанным сюда:
   слова берутся у самой игры (ТЕКСТ_ПРО_ПОДСВЕТКУ, ТЕКСТ_ПАРТИЯ_ОКОНЧЕНА
   и прочие её собственные), а правда проверяется по экрану и по правилам.

   ЧТО ЗАПУСКАТЬ (звать по одному):
     проверки.зелёнаяЧерта(40)     — сорок кругов тычков во всю руку
     проверки.напарник()           — стол парами: что отвечают напарнику
     проверки.послеКонца(6)        — до шести партий, ловим миг после конца
     проверки.быстрыйВторойТап(15) — второй тап через 100 мс
     проверки.отказСнимается(10)
     проверки.мимоКарты(10)
     проверки.всё()
   ===================================================================== */

(function () {
  'use strict';

  const пауза = (мс) => new Promise((r) => setTimeout(r, мс));
  const партияИдёт = () => typeof партия !== 'undefined' && Boolean(партия) && !партия.завершена;
  const строка = () => {
    const у = document.getElementById('подсказка-текст');
    return у ? (у.textContent || '') : '';
  };
  const картыСЧертой = () =>
    document.querySelectorAll('#карты-человека .карта--можно').length;
  const вздрогнувших = () =>
    document.querySelectorAll('#карты-человека .карта--отказ').length;
  const итогПоказан = () => {
    const у = document.getElementById('экран-результата');
    return Boolean(у && у.classList.contains('экран--виден'));
  };

  /** Один законный ход за человека — чтобы стол не стоял. */
  function сходитьЗаконно() {
    if (!партияИдёт() || !сейчасМойХод()) return false;
    рукаГлухаДо = 0;
    const текущая = фаза(партия);
    if (текущая === 'защита') {
      for (let п = 0; п < партия.стол.length; п++) {
        if (партия.стол[п].защита) continue;
        for (let к = 0; к < партия.руки.человек.length; к++) {
          if (бьёт(партия.руки.человек[к], партия.стол[п].атака, партия.козырь)) {
            отбитьсяКартой(п, к); return true;
          }
        }
      }
      нажатьБеру(); return true;
    }
    for (let к = 0; к < партия.руки.человек.length; к++) {
      if (можноПоложить(партия, партия.руки.человек[к])) { сходитьКартой(к); return true; }
    }
    if (мнеМожноЗакончитьПодход(текущая)) { нажатьБито(); return true; }
    return false;
  }

  async function держатьПартиюЖивой() {
    if (партияИдёт()) return;
    начатьПартию();
    await пауза(700);
  }

  /* ------------------------------------------------------------------
     1. Зелёная черта: сказали про неё — пусть она будет.
     ------------------------------------------------------------------ */

  async function зелёнаяЧерта(кругов) {
    const надо = Number(кругов) || 40;
    const итог = {
      проверка: 'сказали «зелёная черта» — а есть ли она',
      словаПроЧерту: ТЕКСТ_ПРО_ПОДСВЕТКУ,
      показовПроЧерту: 0, изНихБезЧерты: 0,
      показовПроПустоту: 0, изНихЧертаБыла: 0,
      враньё: []
    };
    const крайний = Date.now() + 20000 + надо * 3000;
    let круг = 0;
    while (круг < надо && Date.now() < крайний) {
      await держатьПартиюЖивой();
      if (!партияИдёт()) continue;
      const рука = партия.руки.человек ? партия.руки.человек.length : 0;
      for (let к = 0; к < рука; к++) {
        // Двойной тычок: на повтор игра как раз и говорит про подсветку.
        рукаГлухаДо = 0; тапПоКартеЧеловека(к); await пауза(30);
        рукаГлухаДо = 0; тапПоКартеЧеловека(к); await пауза(40);
        const т = строка();
        const черт = картыСЧертой();
        if (т === ТЕКСТ_ПРО_ПОДСВЕТКУ) {
          итог.показовПроЧерту++;
          if (черт === 0) {
            итог.изНихБезЧерты++;
            if (итог.враньё.length < 5) итог.враньё.push(
              'сказано «' + т + '», а карт с чертой в руке 0');
          }
        } else if (т.indexOf('Подходящей карты в руке сейчас нет') === 0) {
          итог.показовПроПустоту++;
          if (черт > 0) {
            итог.изНихЧертаБыла++;
            if (итог.враньё.length < 5) итог.враньё.push(
              'сказано «' + т + '», а карт с чертой в руке ' + черт);
          }
        }
      }
      круг++;
      if (сейчасМойХод()) сходитьЗаконно();
      await пауза(300);
    }
    итог.кругов = круг;
    console.log(итог);
    return итог;
  }

  /* ------------------------------------------------------------------
     2. Стол парами: что отвечают напарнику отбивающегося и правда ли
        его слово возвращается.
     ------------------------------------------------------------------ */

  async function напарник(ждатьСекунд) {
    const крайний = Date.now() + (Number(ждатьСекунд) || 90) * 1000;
    настройкиИгрыСБотами.игроков = 4;
    настройкиИгрыСБотами.парами = true;
    начатьПартию();
    await пауза(800);

    const итог = {
      проверка: 'отбивается напарник — что отвечают и правда ли слово вернётся',
      подходовСНапарником: 0,
      первыеСлова: [], словаНаПовтор: [],
      словоВернулось: 0,            // спросили — обещание сдержано
      партияКончиласьРаньше: 0,     // проверить не вышло, партия успела кончиться
      словоТакИНеВернулось: 0,      // вот это и была бы неправда
      исходы: [],
      тычковБезОтвета: 0
    };

    while (Date.now() < крайний) {
      await пауза(150);
      if (!партияИдёт()) { начатьПартию(); await пауза(800); continue; }
      if (сейчасМойХод()) { сходитьЗаконно(); continue; }
      // Ждём именно того подхода, где отбивается наш напарник.
      const защитник = защищается(партия);
      if (защитник === 'человек' || !самИлиНапарник(партия, защитник, 'человек')) continue;
      if (фаза(партия) === 'атака' || фаза(партия) === 'конец') continue;
      if (!партия.руки.человек.length) continue;

      итог.подходовСНапарником++;
      прошлыеСловаОтказа = '';
      рукаГлухаДо = 0;
      const было = строка();
      тапПоКартеЧеловека(0);
      await пауза(60);
      const первый = строка();
      if (первый === было) итог.тычковБезОтвета++;
      else if (итог.первыеСлова.indexOf(первый) === -1) итог.первыеСлова.push(первый);

      рукаГлухаДо = 0;
      тапПоКартеЧеловека(0);
      await пауза(60);
      const повтор = строка();
      if (повтор !== первый && итог.словаНаПовтор.indexOf(повтор) === -1) {
        итог.словаНаПовтор.push(повтор);
      }

      /* А правда ли слово вернётся? Ждём и смотрим, спросят ли нас.
         Три исхода, и путать их нельзя: спросили; партия успела кончиться
         (тогда обещание не проверено, а не нарушено); прождали всё время
         зря при живой партии — вот это и есть неправда. */
      const ждёмДо = Date.now() + 40000;
      const началоОжидания = Date.now();
      let исход = 'ждали-зря';
      while (Date.now() < ждёмДо) {
        await пауза(150);
        if (!партияИдёт()) { исход = 'партия-кончилась'; break; }
        if (сейчасМойХод()) { исход = 'спросили'; break; }
      }
      итог.исходы.push({ исход: исход, ждалиМс: Date.now() - началоОжидания });
      if (исход === 'спросили') { итог.словоВернулось++; сходитьЗаконно(); }
      else if (исход === 'партия-кончилась') итог.партияКончиласьРаньше++;
      else итог.словоТакИНеВернулось++;
      if (итог.подходовСНапарником >= 6) break;
    }
    console.log(итог);
    return итог;
  }

  /* ------------------------------------------------------------------
     3. Миг после конца партии: плашки итога ещё нет, а нажатия уже
        должны отвечать.
     ------------------------------------------------------------------ */

  async function послеКонца(партийМакс) {
    const надо = Number(партийМакс) || 6;
    const итог = {
      проверка: 'партия окончена, плашки итога ещё нет — отвечают ли нажатия',
      поймано: 0,
      молчаливыхНажатий: 0,
      ответы: []
    };
    for (let i = 0; i < надо && итог.поймано < 3; i++) {
      начатьПартию();
      await пауза(700);
      // Доигрываем как можно быстрее — сами, своими же законными ходами.
      const крайний = Date.now() + 180000;
      while (партияИдёт() && Date.now() < крайний) {
        if (сейчасМойХод()) сходитьЗаконно();
        await пауза(120);
      }
      if (партияИдёт()) continue;          // не успели — берём следующую партию
      if (итогПоказан()) continue;         // плашка обогнала нас, ловим в другой раз

      итог.поймано++;
      const пробы = [];
      const было0 = строка();
      рукаГлухаДо = 0; тапПоКартеЧеловека(0); await пауза(40);
      пробы.push({ куда: 'карта в руке', было: было0, стало: строка() });
      const было1 = строка();
      рукаГлухаДо = 0; тапПоКолоде(); await пауза(40);
      пробы.push({ куда: 'колода', было: было1, стало: строка() });
      const было2 = строка();
      рукаГлухаДо = 0; тапПоКозырю(); await пауза(40);
      пробы.push({ куда: 'козырь', было: было2, стало: строка() });
      const было3 = строка();
      рукаГлухаДо = 0;
      тапМимоКарты({ target: document.getElementById('карты-человека') });
      await пауза(40);
      пробы.push({ куда: 'мимо карты', было: было3, стало: строка() });
      if (партия.стол.length) {
        const было4 = строка();
        рукаГлухаДо = 0; тапПоПаре(0); await пауза(40);
        пробы.push({ куда: 'карта на столе', было: было4, стало: строка() });
      }
      for (const п of пробы) {
        // Ответ засчитан, если игра сказала то, что говорит про конец партии.
        п.ответила = п.стало.indexOf(ТЕКСТ_ПАРТИЯ_ОКОНЧЕНА) !== -1;
        if (!п.ответила) итог.молчаливыхНажатий++;
      }
      итог.ответы.push(пробы);
      await пауза(2500);   // пусть плашка итога всплывёт, прежде чем начинать новую
    }
    console.log(итог);
    return итог;
  }

  /* ------------------------------------------------------------------
     4. Второй быстрый тап по той же карте — вздрагивает ли она заново.
     ------------------------------------------------------------------ */

  async function быстрыйВторойТап(проб) {
    const надо = Number(проб) || 15;
    const итог = {
      проверка: 'второй тап через 100 мс — вздрагивает ли карта полноценно',
      положеноМс: ПОКАЗ_ОТКАЗА,
      проб: 0,
      вздрогнулаНаВторойТап: 0,
      живаЧерез500мс: 0,
      погаслаРаньше: []
    };
    const крайний = Date.now() + 20000 + надо * 4000;
    while (итог.проб < надо && Date.now() < крайний) {
      await держатьПартиюЖивой();
      if (!партияИдёт() || !партия.руки.человек.length) { await пауза(150); continue; }
      // Тычем в карту, которой сейчас нельзя — иначе выйдет законный ход.
      let плохая = -1;
      for (let i = 0; i < партия.руки.человек.length; i++) {
        if (картаСейчасХодит(партия.руки.человек[i]) === false) { плохая = i; break; }
      }
      if (плохая < 0) { if (сейчасМойХод()) сходитьЗаконно(); await пауза(200); continue; }

      рукаГлухаДо = 0; тапПоКартеЧеловека(плохая);
      await пауза(100);                       // второй тап РАНЬШЕ, чем погаснет первый
      рукаГлухаДо = 0; тапПоКартеЧеловека(плохая);
      await пауза(50);
      итог.проб++;
      if (вздрогнувших() > 0) итог.вздрогнувших = (итог.вздрогнувших || 0) + 1;
      if (вздрогнувших() > 0) итог.вздрогнулаНаВторойТап++;
      /* Ключевое: пометка обязана дожить примерно до 700 мс ПОСЛЕ ВТОРОГО
         тапа. Раньше её гасил таймер первого — то есть уже через 600 мс. */
      await пауза(500);
      if (вздрогнувших() > 0) итог.живаЧерез500мс++;
      else if (итог.погаслаРаньше.length < 3) итог.погаслаРаньше.push('проба ' + итог.проб);
      await пауза(400);
      if (сейчасМойХод()) сходитьЗаконно();
      await пауза(200);
    }
    console.log(итог);
    return итог;
  }

  /* ------------------------------------------------------------------
     5. Отказ снимается законным ходом.
     ------------------------------------------------------------------ */

  async function отказСнимается(проб) {
    const надо = Number(проб) || 10;
    const итог = { проверка: 'сделал законный ход — отказ должен уйти сразу',
                   проб: 0, отказУшёл: 0, осталсяВисеть: [] };
    const крайний = Date.now() + 20000 + надо * 4000;
    while (итог.проб < надо && Date.now() < крайний) {
      await держатьПартиюЖивой();
      if (!партияИдёт() || !сейчасМойХод() || !партия.руки.человек.length) { await пауза(150); continue; }
      let плохая = -1;
      for (let i = 0; i < партия.руки.человек.length; i++) {
        if (картаСейчасХодит(партия.руки.человек[i]) === false) { плохая = i; break; }
      }
      if (плохая < 0) { сходитьЗаконно(); await пауза(300); continue; }
      прошлыеСловаОтказа = '';
      рукаГлухаДо = 0; тапПоКартеЧеловека(плохая);
      await пауза(60);
      const отказ = строка();
      if (!сходитьЗаконно()) { await пауза(300); continue; }
      await пауза(60);
      итог.проб++;
      if (строка() !== отказ) итог.отказУшёл++;
      else if (итог.осталсяВисеть.length < 3) итог.осталсяВисеть.push(отказ);
      await пауза(400);
    }
    console.log(итог);
    return итог;
  }

  /* ------------------------------------------------------------------
     6. Промах мимо карты дважды подряд — разными ли словами отвечают.
     ------------------------------------------------------------------ */

  async function мимоКарты(проб) {
    const надо = Number(проб) || 10;
    const итог = { проверка: 'два промаха подряд — слова обязаны отличаться',
                   проб: 0, словаСовпали: 0, примеры: [] };
    const крайний = Date.now() + 20000 + надо * 3000;
    const веер = () => document.getElementById('карты-человека');
    while (итог.проб < надо && Date.now() < крайний) {
      await держатьПартиюЖивой();
      if (!партияИдёт()) { await пауза(150); continue; }
      прошлыеСловаОтказа = '';
      рукаГлухаДо = 0; тапМимоКарты({ target: веер() }); await пауза(50);
      const первый = строка();
      рукаГлухаДо = 0; тапМимоКарты({ target: веер() }); await пауза(50);
      const второй = строка();
      итог.проб++;
      if (первый === второй) итог.словаСовпали++;
      if (итог.примеры.length < 4) итог.примеры.push(первый + ' → ' + второй);
      if (сейчасМойХод()) сходитьЗаконно();
      await пауза(400);
    }
    console.log(итог);
    return итог;
  }

  async function всё() {
    const а = await зелёнаяЧерта(25);
    const б = await быстрыйВторойТап(10);
    const в = await отказСнимается(8);
    const г = await мимоКарты(8);
    const д = await послеКонца(4);
    const е = await напарник(90);
    const итог = { зелёнаяЧерта: а, быстрыйВторойТап: б, отказСнимается: в,
                   мимоКарты: г, послеКонца: д, напарник: е };
    console.log('=== Всё вместе ===', итог);
    return итог;
  }

  window.проверки = { зелёнаяЧерта, напарник, послеКонца, быстрыйВторойТап,
                      отказСнимается, мимоКарты, всё };
  console.log('Проверки готовы. Зовите: проверки.всё() — или по одной.');
})();
