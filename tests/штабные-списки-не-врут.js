'use strict';

/* =====================================================================
   ДВЕ ПРОГРАММЫ ШТАБА НЕ ДОЛЖНЫ ВРАТЬ.

   Владелец дважды ловил нас на неправде в списках. Оба раза врали
   не числа, а признаки, по которым эти числа собирались:

   1. СПИСКИ считали сделанным то, что лежит у исполнителя НА ДИСКЕ.
      Штаб ставил задачу, звал «node штаб/списки.js» — и дело тут же
      уезжало в «Готово», потому что исполнитель успел завести нужную
      строку в файле. Работа при этом не была ни сдана, ни проверена,
      ни опубликована: игрок в нарды попасть не мог, а в списке значилось
      «готово». Готово — это то, что доехало до игроков, то есть до
      опубликованного (origin/main).

   2. СТОРОЖ ПРОСТОЯ ругался на исполнителей, которых уже нет. Он писал
      «оформитель молчит 11 ч 26 мин», пока оформитель работал: смотрел
      на файл записей ВЧЕРАШНЕГО оформителя. Мёртвый файл не растёт,
      и со стороны это неотличимо от молчания живого.

   Проверка держит оба признака. Она нарочно не трогает живые данные
   штаба (штаб/списки.json, штаб/в-работе.json): те правятся прямо
   во время работы, и проверка, которая от них зависит, краснела бы
   от чужих правок. Здесь всё на своих, поддельных.

   Запуск:
       node tests/штабные-списки-не-врут.js
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const os = require('os');

const КОРЕНЬ = path.join(__dirname, '..');
const сделано = require(path.join(КОРЕНЬ, 'штаб', 'сделано.js'));
const сторож = require(path.join(КОРЕНЬ, 'штаб', 'кто-молчит.js'));

let проверок = 0;
const провалы = [];

function проверить(условие, что) {
  проверок++;
  if (условие) {
    console.log('  ок   ' + что);
    return;
  }
  провалы.push(что);
  console.log('  ПРОВАЛ: ' + что);
}

/* ---------------------------------------------------------------------
   1. Списки: сделанным считается только опубликованное
   --------------------------------------------------------------------- */

console.log('=== Списки не считают сделанным то, чего нет у игроков ===\n');
console.log('1. Файл есть на диске, в опубликованном его нет');

/* Заводим на диске файл, которого заведомо нет в origin/main: имя
   с меткой времени. Для игрока такого файла не существует. */
const имяТолькоНаДиске = 'штаб/только-на-диске-' + Date.now() + '.js';
fs.writeFileSync(path.join(КОРЕНЬ, имяТолькоНаДиске),
  '// временный файл проверки: обещанная строка тут есть\nфункцияИзОбещания();\n');

try {
  const пункт = {
    что: 'Дело, которого у игроков ещё нет',
    сделано: { файл: имяТолькоНаДиске, есть: 'функцияИзОбещания' }
  };
  const разбор = сделано.разобратьПункт(пункт, сделано.записиGit(50) || []);
  проверить(разбор.сделан === false,
    'дело осталось в очереди: на диске есть, у игроков нет');
  проверить(String(разбор.чем || '').indexOf('опубликован') !== -1,
    'причина названа словами про публикацию, а не «файла нет»');

  /* А теперь то же самое, но про файл, который в публикации ЕСТЬ.
     Без этой половины проверка была бы зелёной всегда — даже если
     программа перестанет вычёркивать вообще что-либо. */
  console.log('\n2. Опубликованное дело всё-таки вычёркивается');
  const живой = {
    что: 'Дело, которое давно у игроков',
    сделано: { файл: 'js/telegram.js', есть: 'function' }
  };
  const разборЖивого = сделано.разобратьПункт(живой, сделано.записиGit(50) || []);
  проверить(разборЖивого.сделан === true,
    'дело, которое есть в опубликованном, помечено сделанным');
  проверить(разборЖивого.когда instanceof Date,
    'время взято настоящее — из записей git, а не из головы');
} finally {
  fs.unlinkSync(path.join(КОРЕНЬ, имяТолькоНаДиске));
}

/* ---------------------------------------------------------------------
   2. Сторож простоя: след прежнего запуска — не молчание
   --------------------------------------------------------------------- */

console.log('\n=== Сторож простоя не будит из-за вчерашних следов ===');

/* Поддельные записи: два файла — «живой» и «от прежнего запуска».
   Кладём их в свою временную папку и подсовываем сторожу. */
const песочница = fs.mkdtempSync(path.join(os.tmpdir(), 'штаб-сторож-'));
const час = 60 * 60 * 1000;
const сейчас = Date.now();

function положить(имя, размер, когдаМенялся) {
  const путь = path.join(песочница, имя + '.output');
  fs.writeFileSync(путь, 'x'.repeat(размер));
  fs.utimesSync(путь, new Date(когдаМенялся), new Date(когдаМенялся));
  return { имя: имя, изменён: new Date(когдаМенялся), размер: размер };
}

const записи = [
  // Живой: работу поставили три часа назад, он писал час назад.
  положить('живой111', 500, сейчас - час),
  // Прежний запуск: файл не менялся со вчера, работа поставлена сегодня.
  положить('мёртвый22', 900, сейчас - 20 * час)
];

const работы = [
  { кто: 'живой исполнитель', что: 'что-то делает', задача: 'живой111',
    начато: new Date(сейчас - 3 * час).toISOString() },
  { кто: 'вчерашний оформитель', что: 'его уже нет', задача: 'мёртвый22',
    начато: new Date(сейчас - 2 * час).toISOString() }
];

const итог = сторож.собрать(30, false, { записи: записи, работы: работы });
const поИмени = {};
for (const строка of итог.строки || []) поИмени[строка.кто] = строка;

проверить(Boolean(поИмени['живой исполнитель']) && Boolean(поИмени['вчерашний оформитель']),
  'сторож разобрал обе работы');

if (поИмени['живой исполнитель'] && поИмени['вчерашний оформитель']) {
  const живой = поИмени['живой исполнитель'];
  const прежний = поИмени['вчерашний оформитель'];

  проверить(живой.состояние === 'молчит' || живой.состояние === 'редко пишет',
    'живой, который час не писал, в тревоге остаётся (состояние «' + живой.состояние + '»)');
  проверить(прежний.состояние === 'след устарел',
    'вчерашний след не считается молчанием (состояние «' + прежний.состояние + '»)');
  проверить(String(прежний.слова).indexOf('прежнего запуска') !== -1,
    'сторож объясняет словами, что номер задачи устарел');
}

/* Убираем за собой: временные файлы не должны копиться. */
for (const имя of fs.readdirSync(песочница)) fs.unlinkSync(path.join(песочница, имя));
fs.rmdirSync(песочница);

console.log('\n----------------------------------------');
console.log('Проверок сделано: ' + проверок);
console.log('ПРОВАЛОВ: ' + провалы.length);
process.exit(провалы.length === 0 ? 0 : 1);
