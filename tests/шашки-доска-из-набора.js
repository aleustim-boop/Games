/* ==================================================================
   ЧАСТЬ 1 — БЕЗ БРАУЗЕРА: файлы набора на диске, разметка в html.
   ================================================================== */
function частьБезБраузера() {
  console.log('=== Без браузера: файлы набора и разметка ===');

  const путьCSS = path.join(КОРЕНЬ, 'style-шашки.css');
  const css = fs.readFileSync(путьCSS, 'utf8');
  // Пути url(...) читаем ИЗ САМОГО css — переписанный руками список
  // однажды разойдётся с настоящим. Корону дамки CSS рисует кодом
  // (data:image/svg+xml,…) — это не файл набора, и такие url() в проверку
  // существования файлов не идут (data: и http(s) отбрасываем нарочно).
  const все = [...css.matchAll(/url\(\s*['"]?([^'")]+)['"]?\s*\)/g)].map((м) => м[1]);
  const пути = все.filter((п) => !/^data:/.test(п) && !/^https?:/.test(п));
  проверить(пути.length >= 7, 'в style-шашки.css есть url(...) набора (без data:): ' + пути.length);
  console.log('  путей в css: ' + пути.length + ' из ' + все.length + ' url() всего');
  for (const путь of пути) {
    const полный = path.join(КОРЕНЬ, путь.split('?')[0]);
    проверить(fs.existsSync(полный), 'файл набора на месте: ' + путь);
  }

  const html = fs.readFileSync(path.join(КОРЕНЬ, 'шашки.html'), 'utf8');
  проверить(!/шашки-доска-вид\.js/.test(html),
    'в шашки.html нет подключения js/шашки-доска-вид.js');
  проверить(!/id=["']экран-оформления["']/.test(html),
    'в шашки.html нет id="экран-оформления"');
  проверить(!/id=["']кнопка-лист-игры-оформление["']/.test(html),
    'в шашки.html нет id="кнопка-лист-игры-оформление"');
  проверить(!fs.existsSync(path.join(КОРЕНЬ, 'js', 'шашки-доска-вид.js')),
    'файла js/шашки-доска-вид.js на диске больше нет');
}

