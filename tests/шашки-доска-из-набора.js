/** Общие проверки вида доски: шашки, подписи, буквы снизу. Одинаковы
 *  для обоих размеров экрана — доска рисуется тем же кодом. Годятся
 *  только для СТАРТОВОЙ позиции: 24 шашки на доске, боя ещё не было. */
async function проверитьОбщийВидДоски(страница, подпись) {
  const данные = await страница.evaluate(() => {
    const шашки = [...document.querySelectorAll('#доска .фишка')];
    const разбор = шашки.map((ф) => ({
      classList: [...ф.classList],
      фон: getComputedStyle(ф).backgroundImage
    }));
    const метокВРамке = document.querySelectorAll('.доска-шашек-рамка > .метка-буква, .доска-шашек-рамка > .метка-цифра').length;
    const метокВКлетках = document.querySelectorAll('.поле .метка-буква, .поле .метка-цифра').length;
    const буквы = [...document.querySelectorAll('.метка-буква')]
      .sort((а, б) => а.getBoundingClientRect().left - б.getBoundingClientRect().left)
      .map((у) => у.textContent.trim());
    return { всего: разбор.length, разбор: разбор, метокВРамке: метокВРамке, метокВКлетках: метокВКлетках, буквы: буквы };
  });

  проверить(данные.всего === 24, подпись + ': на доске 24 узла .фишка, вышло ' + данные.всего);
  const уКаждойФон = данные.разбор.every((ф) => ф.фон && ф.фон !== 'none');
  проверить(уКаждойФон, подпись + ': у каждой шашки background-image не «none»' +
    (уКаждойФон ? '' : ' (испорчена: ' + JSON.stringify(данные.разбор.find((ф) => !ф.фон || ф.фон === 'none')) + ')'));

  проверить(данные.метокВРамке === 16, подпись + ': меток в рамке 16, вышло ' + данные.метокВРамке);
  проверить(данные.метокВКлетках === 0, подпись + ': меток внутри клеток 0, вышло ' + данные.метокВКлетках);
  проверить(данные.буквы.join('') === 'abcdefgh',
    подпись + ': буквы снизу слева направо a…h, вышло «' + данные.буквы.join('') + '»');

  return данные;
}

