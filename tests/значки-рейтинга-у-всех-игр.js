'use strict';

/* =====================================================================
   ЗНАЧКИ РЕЙТИНГА У ВСЕХ ИГР — проверка, что каждая игра из рейтинга
   имеет два файла значков правильного размера.

   Проверяет только игры с флагом вРейтинге: true из js/игры-реестр.js.
   Каждая такая игра обязана иметь:
   — img/рейтинг/<ключ>.png (квадрат WxW)
   — img/рейтинг/<ключ>@2x.png (квадрат 2W×2W)

   @2x файл должен быть ровно вдвое больше по каждой стороне.

   Размер проверяется чтением заголовка PNG без библиотек:
   смещение 16 (ширина, big-endian), смещение 20 (высота, big-endian).

   Запуск:
       node tests/значки-рейтинга-у-всех-игр.js              — проект
       node tests/значки-рейтинга-у-всех-игр.js --папка=<путь> — иная папка значков
       node tests/значки-рейтинга-у-всех-игр.js --сломать    — ломающий запуск:
         копирует папку значков во временную папку, удаляет один
         существующий значок и требует провала
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

const ПРОЕКТ = path.join(__dirname, '..');

/**
 * Прочитать размеры PNG из заголовка без библиотек.
 * Возвращает { ширина, высота } или null, если файл не PNG или не читается.
 */
function прочитатьРазмерПNG(путьКФайлу) {
  try {
    if (!fs.existsSync(путьКФайлу)) return null;
    const буфер = Buffer.alloc(24);
    const дескр = fs.openSync(путьКФайлу, 'r');
    fs.readSync(дескр, буфер, 0, 24);
    fs.closeSync(дескр);

    // Проверить сигнатуру PNG: 89 50 4E 47 0D 0A 1A 0A
    const сигнатура = [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A];
    for (let i = 0; i < 8; i++) {
      if (буфер[i] !== сигнатура[i]) return null;
    }

    // Смещение 16: ширина (big-endian), смещение 20: высота (big-endian)
    const ширина = буфер.readUInt32BE(16);
    const высота = буфер.readUInt32BE(20);
    return { ширина, высота };
  } catch (ошибка) {
    return null;
  }
}

/**
 * Проверить один корень (проект или копию). Возвращает счёт провалов.
 */
function проверитьКорень(КОРЕНЬ, папкаЗначков) {
  const итог = { проверок: 0, провалы: [] };

  function сказать(т) {
    console.log(т);
  }

  function провалить(текст) {
    итог.провалы.push(текст);
    сказать('  ПРОВАЛ: ' + текст);
  }

  // Загрузить реестр
  let реестр = [];
  try {
    const путь = path.join(КОРЕНЬ, 'js', 'игры-реестр.js');
    delete require.cache[path.resolve(путь)];
    реестр = require(путь).все();
  } catch (ошибка) {
    провалить('не читается js/игры-реестр.js: ' + ошибка.message);
    return итог;
  }

  if (реестр.length === 0) {
    провалить('реестр игр пуст — проверять нечего');
    return итог;
  }

  // Отфильтровать только игры с вРейтинге: true
  const игрыРейтинга = реестр.filter(function (и) { return и.вРейтинге === true; });
  if (игрыРейтинга.length === 0) {
    провалить('в реестре нет ни одной игры с вРейтинге: true');
    return итог;
  }

  сказать('Корень: ' + КОРЕНЬ);
  сказать('Папка значков: ' + папкаЗначков);
  сказать('Игр в реестре: ' + реестр.length + ', с флагом вРейтинге: true — ' + игрыРейтинга.length + '\n');

  // Проверить значки для каждой игры рейтинга
  игрыРейтинга.forEach(function (игра) {
    const ключ = игра.ключ;
    const файлОдин = path.join(папкаЗначков, ключ + '.png');
    const файлДва = path.join(папкаЗначков, ключ + '@2x.png');

    // Проверить первый файл (должен быть квадратом)
    итог.проверок++;
    const размерОдин = прочитатьРазмерПNG(файлОдин);
    if (!размерОдин) {
      провалить('«' + ключ + '» ' + файлОдин + ' не найден или не PNG');
    } else if (размерОдин.ширина !== размерОдин.высота) {
      провалить('«' + ключ + '» ' + файлОдин + ' размер ' + размерОдин.ширина + '×' + размерОдин.высота + ', требуется квадрат');
    } else {
      сказать('ок     ' + ключ + ' (' + размерОдин.ширина + 'x' + размерОдин.высота + ')');
    }

    // Проверить второй файл (@2x должен быть ровно вдвое больше)
    итог.проверок++;
    const размерДва = прочитатьРазмерПNG(файлДва);
    if (!размерДва) {
      провалить('«' + ключ + '» ' + файлДва + ' не найден или не PNG');
    } else if (размерДва.ширина !== размерДва.высота) {
      провалить('«' + ключ + '» ' + файлДва + ' размер ' + размерДва.ширина + '×' + размерДва.высота + ', требуется квадрат');
    } else if (размерОдин && (размерДва.ширина !== размерОдин.ширина * 2 || размерДва.высота !== размерОдин.высота * 2)) {
      провалить('«' + ключ + '» @2x размер ' + размерДва.ширина + '×' + размерДва.высота + ', требуется ' + (размерОдин.ширина * 2) + '×' + (размерОдин.высота * 2));
    } else if (размерОдин) {
      сказать('ок     ' + ключ + '@2x (' + размерДва.ширина + 'x' + размерДва.высота + ')');
    }
  });

  return итог;
}

/**
 * Ломающий запуск: удалить один значок и требовать провала.
 */
function ломающийЗапуск(папкаЗначков) {
  console.log('Ломающий запуск --сломать: удалим один значок из копии.\n');

  // Скопировать папку значков во временную
  const временнаяПапка = fs.mkdtempSync(path.join(os.tmpdir(), 'значки-рейтинга-'));
  const копияПапки = path.join(временнаяПапка, 'рейтинг');
  fs.cpSync(папкаЗначков, копияПапки, { recursive: true });

  // Загрузить реестр, чтобы найти первую игру рейтинга (дурак)
  let реестр = [];
  try {
    const путь = path.join(ПРОЕКТ, 'js', 'игры-реестр.js');
    delete require.cache[path.resolve(путь)];
    реестр = require(путь).все();
  } catch (ошибка) {
    console.log('ОШИБКА: не читается реестр: ' + ошибка.message);
    fs.rmSync(временнаяПапка, { recursive: true, force: true });
    process.exit(1);
  }

  // Найти первую игру с вРейтинге: true
  let игра = null;
  for (let i = 0; i < реестр.length; i++) {
    if (реестр[i].вРейтинге === true) {
      игра = реестр[i];
      break;
    }
  }

  if (!игра) {
    console.log('ОШИБКА: в реестре нет ни одной игры с вРейтинге: true');
    fs.rmSync(временнаяПапка, { recursive: true, force: true });
    process.exit(1);
  }

  const ключПорчи = игра.ключ;
  const файлПорчи = path.join(копияПапки, ключПорчи + '.png');

  console.log('Удаляем значок: ' + файлПорчи);
  try {
    fs.unlinkSync(файлПорчи);
  } catch (ошибка) {
    console.log('ОШИБКА: не удаётся удалить файл: ' + ошибка.message);
    fs.rmSync(временнаяПапка, { recursive: true, force: true });
    process.exit(1);
  }

  // Проверить копию — обязана найти ошибку
  console.log('');
  const итог = проверитьКорень(ПРОЕКТ, копияПапки);

  // Очистить временную папку
  fs.rmSync(временнаяПапка, { recursive: true, force: true });

  // Проверить, что ошибка найдена ровно на удалённом ключе
  const нужнаяОшибка = итог.провалы.some(function (п) {
    return п.indexOf('«' + ключПорчи + '»') !== -1 && п.indexOf('.png') !== -1;
  });

  console.log('');
  if (нужнаяОшибка) {
    console.log('Ожидали ошибку на «' + ключПорчи + '»: найдена ✓');
    console.log('Итого проверок: 1, провалов: 0');
    process.exit(0);
  } else {
    console.log('Ожидали ошибку на «' + ключПорчи + '»: СЛЕПА ✗');
    console.log('Итого проверок: 1, провалов: 1');
    process.exit(1);
  }
}

/* ---- Запуск ---- */

let довод = process.argv.find(function (а) { return а.indexOf('--папка') === 0; });
let папкаЗначков = ПРОЕКТ;
if (довод) {
  const префикс = '--папка=';
  if (довод.indexOf(префикс) === 0) {
    папкаЗначков = path.resolve(довод.slice(префикс.length));
  }
} else {
  папкаЗначков = path.join(ПРОЕКТ, 'img', 'рейтинг');
}

if (process.argv.indexOf('--сломать') !== -1) {
  ломающийЗапуск(папкаЗначков);
} else {
  const итог = проверитьКорень(ПРОЕКТ, папкаЗначков);
  console.log('');
  console.log('Итого проверок: ' + итог.проверок + ', провалов: ' + итог.провалы.length);
  process.exit(итог.провалы.length ? 1 : 0);
}
