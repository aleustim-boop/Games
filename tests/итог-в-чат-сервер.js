/**
 * Сыграть шашки за только что открытым столом: дорассадить двоих (если
 * создатель уже сидит — он первый), нажать «Начать» (у стола без хозяина —
 * первый севший, он же хозяин; если партия началась сама, отказ не важен),
 * второй сдаётся. Вернуть рассаженных и ответ на сдачу.
 */
async function сыграть(создание, создатель, входящие) {
  const места = [];
  if (создание.тело.пропуск) места.push({ код: создание.тело.код, пропуск: создание.тело.пропуск, кто: создатель });
  let и = 0;
  while (места.length < 2 && и < входящие.length) {
    const кто = входящие[и++];
    const тело = { код: создание.тело.код, имя: кто.имяВИгре };
    if (кто.номер) тело.initData = подписьИгрока(кто.номер, кто.имяВПодписи);
    const вход = await спросить('/войти', тело);
    if (вход.тело.пропуск) места.push({ код: вход.тело.код || создание.тело.код, пропуск: вход.тело.пропуск, кто: кто });
  }
  if (места.length < 2) return { места: места, сдача: null };
  await спросить('/ход', { код: места[0].код, пропуск: места[0].пропуск, действие: 'начать' });
  const сдача = await спросить('/ход', { код: места[1].код, пропуск: места[1].пропуск, действие: 'сдаться' });
  return { места: места, сдача: сдача };
}

/* Ждём сообщений в группы по числу, потом тишину — не придёт ли лишнее. */
const ПОТОЛОК_ЖДАТЬ = 3000;
const ТИШИНА = 300;
let контрольноеВремя = 0;

async function дождатьсяСообщений(отметка, сколько) {
  const начало = Date.now();
  let число = вГруппыПосле(отметка).length;
  let перемена = начало;
  while (Date.now() - начало < ПОТОЛОК_ЖДАТЬ) {
    await пауза(10);
    const сейчас = вГруппыПосле(отметка).length;
    if (сейчас !== число) { число = сейчас; перемена = Date.now(); }
    if (число >= сколько && Date.now() - перемена >= ТИШИНА) break;
  }
  return Date.now() - начало;
}

/** Где сообщений быть не должно: ждём не меньше, чем шло контрольное, и не меньше тишины. */
function ждатьКакКонтрольное() {
  return пауза(Math.max(контрольноеВремя, ТИШИНА));
}

