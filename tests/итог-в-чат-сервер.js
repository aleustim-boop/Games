/* ---------------------------------------------------------------------
   Сверка 4: номер группы не утекает в ответы
   --------------------------------------------------------------------- */
function проверитьОтветы() {
  настоящийЛог('4. Ответы сервера без номера группы');
  const состояний = всеОтветы.filter(function (о) { return о.путь === '/состояние'; }).length;
  проверить(состояний >= 2, '4: опора — ответов /состояние собрано ' + состояний);
  проверить(всеОтветы.length >= 10, '4: опора — ответов всего ' + всеОтветы.length);
  /* Число целиком, а не кусок чужого числа (метки времени длинные). */
  const номерЦеликом = new RegExp('(^|[^0-9])' + ЧАТ_СТРОКОЙ.slice(1) + '([^0-9]|$)');
  const протёкшие = всеОтветы.filter(function (о) {
    return номерЦеликом.test(о.текст) || о.текст.indexOf('чатСтола') !== -1;
  });
  проверить(протёкшие.length === 0, '4: ни в одном ответе нет ' + ЧАТ + ' и поля чатСтола (протекло в: ' +
    протёкшие.map(function (о) { return о.путь; }).join(', ') + ')');
}

/* ---------------------------------------------------------------------
   Сверка 5: Telegram не принял итог в группу — личные письма всё равно
   уходят, сервер жив и не падает
   --------------------------------------------------------------------- */
function личныеПосле(отметка, номер) {
  return журнал.slice(отметка).filter(function (з) {
    return з.метод === 'sendMessage' && Number(з.тело && з.тело.chat_id) === номер;
  });
}

/** Ждать, пока уйдут сколько личных писем и хоть одна попытка в группу, потом тишина. */
async function дождатьсяЛичныхИГруппы(отметка, номера) {
  const начало = Date.now();
  let перемена = начало;
  let было = -1;
  while (Date.now() - начало < 5000) {
    await пауза(20);
    const число = журнал.slice(отметка).filter(function (з) { return з.метод === 'sendMessage'; }).length;
    if (число !== было) { было = число; перемена = Date.now(); }
    const личных = номера.reduce(function (с, н) { return с + личныеПосле(отметка, н).length; }, 0);
    if (личных >= номера.length && вГруппыПосле(отметка).length >= 1 && Date.now() - перемена >= 600) break;
  }
}

async function проверитьСбойЧата() {
  настоящийЛог('5. Telegram не принял итог в группу (500, обрыв, отказ, исключение)');
  const режимы = [
    ['опора: Telegram принял', 'принял'],
    ['ответил 500', '500'],
    ['соединение оборвалось (ответа нет)', 'пусто'],
    ['обещание отвергнуто', 'отвергнуто'],
    ['труба бросила исключение сразу', 'исключение']
  ];
  const пропуск = сервера.пропускБотаИзТокена(ТОКЕН_ДЛЯ_ПРОБЫ);
  for (const [как, режим] of режимы) {
    итогВЧат.забытьВсё();
    итогВБот.забытьВсё();
    режимЧата = режим;
    const отброшеноДо = необработанных;
    const создание = await запроситьСтолОтБота(ЧАТ, пропуск);
    проверить(создание.код === 200 && Boolean(создание.тело.код), '5 ' + как + ': стол открыт');
    const а = новыйЧеловек('Ира');
    const б = новыйЧеловек('Кирилл');
    const отметка = журнал.length;
    const итоговДо = итоги.length;
    const партия = await сыграть(создание, null, [а, б]);
    проверить(Boolean(партия.сдача) && партия.сдача.тело.принято === true, '5 ' + как + ': партия сыграна, сдача принята');
    await дождатьсяЛичныхИГруппы(отметка, [а.номер, б.номер]);
    проверить(итоги.length === итоговДо + 1, '5 ' + как + ': «итог» объявлен ровно один раз (' + (итоги.length - итоговДо) + ')');
    проверить(вГруппыПосле(отметка).length === 1, '5 ' + как + ': в группу была ровно одна попытка (' + вГруппыПосле(отметка).length + ')');
    проверить(личныеПосле(отметка, а.номер).length === 1 && личныеПосле(отметка, б.номер).length === 1,
      '5 ' + как + ': личные итоги обоим всё равно ушли (' + личныеПосле(отметка, а.номер).length + ' и ' + личныеПосле(отметка, б.номер).length + ')');
    /* Сервер жив: отвечает и на состояние, и на новый стол. */
    const место = партия.места[0];
    const состояние = место ? await спросить('/состояние', { код: место.код, пропуск: место.пропуск }) : { код: 0 };
    проверить(состояние.код === 200, '5 ' + как + ': сервер отвечает на /состояние (код ' + состояние.код + ')');
    const новый = await запроситьСтолОтБота(ЧАТ, пропуск);
    проверить(новый.код === 200 && Boolean(новый.тело.код), '5 ' + как + ': сервер открывает новый стол');
    await пауза(100);
    проверить(необработанных === отброшеноДо, '5 ' + как + ': необработанных отказов в процессе нет (' + (необработанных - отброшеноДо) + ')');
  }
  режимЧата = 'принял';
}

function портСвободен(порт) {
  return new Promise(function (готово) {
    const проба = net.createServer();
    проба.once('error', function () { готово(false); });
    проба.once('listening', function () { проба.close(function () { готово(true); }); });
    проба.listen(порт, ХОСТ);
  });
}

