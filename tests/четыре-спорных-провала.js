/* Порядок перебора карт — со случайного места, а не всегда с первой.
   Иначе оба игрока ходят одинаково партию за партией, дураком остаётся
   вечно один и тот же, и вторая половина правила («а если дураком стал
   другой?») не проверяется ни разу. */
function вразнобой(сколько) {
  const порядок = [];
  for (let н = 0; н < сколько; н++) порядок.push(н);
  for (let н = порядок.length - 1; н > 0; н--) {
    const м = Math.floor(выборХода() * (н + 1));
    const запас = порядок[н]; порядок[н] = порядок[м]; порядок[м] = запас;
  }
  return порядок;
}

async function походитьЗаСебя(игрок) {
  const вид = игрок.вид || {};
  const рука = вид.мояРука || [];
  /* Поддавки. Кому в этой партии быть дураком, назначается заранее и по
     очереди — иначе один и тот же игрок проигрывал бы все партии подряд,
     и вторая половина правила («а если дураком стал ДРУГОЙ?») не
     проверялась бы ни разу. Проверено: без этого за четырнадцать партий
     дураком четырнадцать раз подряд оставался второй. */
  /* Кто сейчас отбивается. Поля «яОтбиваюсь» в старой комнате на двоих
     нет вовсе (сервер кладёт его только для стола компанией), а «яХожу»
     для этого не годится: в защите слово принадлежит как раз защитнику,
     и «яХожу» у него true. Вдвоём защитник — это просто тот, кто не
     нападает. */
  const яЗащитник = вид.яАтакую === false;

  if (игрок.поддаётся && вид.фаза === 'защита' && яЗащитник) {
    const о = await действие(игрок, { действие: 'беру' });
    if (о.тело && о.тело.принято) return 'беру';
  }
  if (вид.фаза === 'защита' && яЗащитник) {
    // Отбиваемся честно и до последнего: всеми картами по всем парам.
    for (const к of вразнобой(рука.length)) {
      for (const пара of вразнобой((вид.стол || []).length)) {
        const о = await действие(игрок, { действие: 'отбить', карта: к, пара: пара });
        if (о.тело && о.тело.принято) return 'отбить';
      }
    }
  }
  /* Тот, кому назначено проиграть, ещё и подкидывает поменьше: карты
     остаются у него на руках, а этого и надо. */
  const подкидыватьЛи = !(игрок.поддаётся && (вид.стол || []).length > 0);
  if (подкидыватьЛи) {
    for (const к of вразнобой(рука.length)) {
      const о = await действие(игрок, { действие: 'ходить', карта: к });
      if (о.тело && о.тело.принято) return 'ходить';
    }
  }
  for (const слово of ['бито', 'беру', 'пас']) {
    const о = await действие(игрок, { действие: слово });
    if (о.тело && о.тело.принято) return слово;
  }
  return null;
}

/** Доиграть партию до конца, сверяя рассказ после каждого действия. */
async function доигратьПартию(первый, второй) {
  for (let шаг = 0; шаг < ПРЕДЕЛ_ШАГОВ; шаг++) {
    await состояние(первый);
    await состояние(второй);
    if (первый.вид.завершена || второй.вид.завершена) return true;

    let ктоТоХодил = false;
    for (const [игрок, сосед] of [[первый, второй], [второй, первый]]) {
      await состояние(игрок);
      if (игрок.вид.завершена) return true;
      const рукаБыла = (игрок.вид.мояРука || []).length;
      const что = await походитьЗаСебя(игрок);
      if (что) {
        ктоТоХодил = true;
        /* Наблюдаемый факт, а не пересказ правила: он положил карту, и рука
           у него стала короче ровно на одну. Значит, событие точно про него. */
        const рукаСтала = (игрок.вид.мояРука || []).length;
        const точноПроНего = (что === 'ходить' || что === 'отбить') && рукаБыла - рукаСтала === 1;
        await сверитьРассказ(игрок, сосед, что, точноПроНего);
      }
    }
    if (!ктоТоХодил) return false;
  }
  return false;
}

/** Чем партия кончилась для этого игрока — спрашиваем сервер, не считаем сами. */
function дуракПоИтогам(первый, второй) {
  if (первый.вид.итог === 'ничья' || второй.вид.итог === 'ничья') return 'ничья';
  if (первый.вид.итог === 'поражение') return партии.ПЕРВЫЙ;
  if (второй.вид.итог === 'поражение') return партии.ВТОРОЙ;
  return null;
}

