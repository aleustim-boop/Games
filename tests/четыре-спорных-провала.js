function спросить(путь, тело) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН_АДРЕС, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (ч) { текст += ч; });
      ответ.on('end', function () {
        try { готово({ код: ответ.statusCode, тело: JSON.parse(текст || '{}') }); }
        catch (е) { готово({ код: ответ.statusCode, тело: null }); }
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

async function состояние(игрок) {
  const о = await спросить('/состояние', { код: игрок.код, пропуск: игрок.пропуск });
  игрок.вид = (о.тело && о.тело.состояние) || {};
  return игрок.вид;
}

async function действие(игрок, что) {
  const о = await спросить('/ход', Object.assign({ код: игрок.код, пропуск: игрок.пропуск }, что));
  if (о.тело && о.тело.состояние) игрок.вид = о.тело.состояние;
  return о;
}

/* ---------------------------------------------------------------------
   Проверка №1: рассказ об одном ходе — глазами обоих

   Слова здесь не сверяются ни с чем. Сверяется только то, что сервер
   сам объявил своим железным правилом.
   --------------------------------------------------------------------- */

/* «Это рассказ про меня» узнаётся по слову «Вы» в начале — так велит
   само правило, записанное в server/партия-по-сети.js: «рассказ ПРО СЕБЯ
   всегда начинается со слова „Вы“. По этой примете проверки отличают
   „я сам это сделал“ от „это сделал другой“». Больше ни одного слова
   отсюда не сверяется. */
function проСебя(текст) {
  return /^Вы[\s,]/.test(текст || '');
}

function типСтроки(что) {
  return typeof что === 'string' && что.trim().length > 0;
}

/**
 * Сверить один рассказ, каким его увидели оба игрока.
 *
 * Внимание: «кто нажал кнопку» и «с кем случилось событие» — РАЗНЫЕ люди,
 * и это нарочно. Подход заканчивает подкидывающий («Бито»), а карты
 * со стола при этом забирает отбивавшийся, и рассказ про забор карт
 * достаётся ему. Поэтому здесь не проверяется «нажавший читает про себя» —
 * проверяется другое, и оно верно всегда: про одно событие ровно ОДИН
 * из двоих читает «Вы...», а второй — про соседа.
 */
async function сверитьРассказ(первый, второй, чтоСделал, точноПроПервого) {
  const а = await состояние(первый);
  const б = await состояние(второй);

  // Оба должны смотреть на одно и то же событие, иначе сравнивать нечего.
  if (а.номерСобытия !== б.номерСобытия) return;
  if (!а.видСобытия && !б.видСобытия) return;

  событийСверено++;

  проверить(а.видСобытия === б.видСобытия,
    'об одном и том же событии сервер сказал двоим разное: одному «' + а.видСобытия +
    '», другому «' + б.видСобытия + '»');

  проверить(типСтроки(а.событие) && типСтроки(б.событие),
    'после действия «' + чтоСделал + '» рассказ обязан быть у обоих, а пришло: ' +
    JSON.stringify(а.событие) + ' и ' + JSON.stringify(б.событие));
  if (!типСтроки(а.событие) || !типСтроки(б.событие)) return;

  if (а.событие === б.событие) {
    /* Событие, которое касается обоих сразу («карты розданы», «играем
       ещё»): текст один на двоих, и «Вы» в нём быть не должно. */
    проверить(!проСебя(а.событие) && !проСебя(б.событие),
      'общее событие («' + а.видСобытия + '») написано от лица одного из двоих: «' + а.событие + '»');
    return;
  }

  const своих = (проСебя(а.событие) ? 1 : 0) + (проСебя(б.событие) ? 1 : 0);
  проверить(своих === 1,
    'про событие «' + а.видСобытия + '» читать «Вы...» обязан ровно один из двоих, а таких ' +
    своих + ': «' + а.событие + '» и «' + б.событие + '»');

  /* А в тех случаях, когда мы ТОЧНО ЗНАЕМ, с кем случилось событие,
     сверяем ещё и это. Знаем не по списку событий, который пришлось бы
     держать у себя, а по наблюдаемому факту: игрок положил карту, и у него
     на руке стало на одну меньше. Значит, рассказ про себя обязан читать
     он, а не сосед. Без этой сверки поменяй кто-нибудь местами половинки
     «своё» и «чужое» — и оба читали бы про чужой ход как про свой,
     а проверка бы этого не увидела. */
  if (точноПроПервого) {
    проверить(проСебя(а.событие),
      'карту положил один игрок, а рассказ про себя достался другому: положивший читает «' +
      а.событие + '», а сосед — «' + б.событие + '»');
  }
}

/* ---------------------------------------------------------------------
   Проверка №2: кто нападает в новой партии

   Правило спрашиваем у игры. Своей копии здесь нет: именно на копии
   штатная проверка и застряла в августе.
   --------------------------------------------------------------------- */

/** Кто обязан нападать, если дураком прошлой партии остался вот этот. */
function ктоОбязанНападать(дурак) {
  const стол = { игроки: [партии.ПЕРВЫЙ, партии.ВТОРОЙ] };
  return игра.ктоХодитНаДурака(стол, дурак);
}

