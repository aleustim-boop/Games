/* Вырезать из исходника функцию по началу её объявления до закрывающей
   скобки на том же отступе. Не нашлась — это провал, а не пропуск. */
function вырезать(исходник, начало) {
  const от = исходник.indexOf(начало);
  if (от === -1) throw new Error('не найдено в сеть.js: «' + начало.trim() + '»');
  const конец = /\r?\n  \}\r?\n/g;
  конец.lastIndex = от;
  const н = конец.exec(исходник);
  if (!н) throw new Error('не найден конец функции «' + начало.trim() + '»');
  return исходник.slice(от, н.index + н[0].length);
}

function собратьПоколения(сеть) {
  if (сеть.indexOf('let поколение = 0;') === -1) throw new Error('не найдено в сеть.js: «let поколение = 0;»');
  const код = [
    'let поколение = 0;',
    вырезать(сеть, '  function новоеПоколение('),
    вырезать(сеть, '  function ответУстарел('),
    вырезать(сеть, '  function попробоватьВернуться('),
    'globalThis.дай = { попробоватьВернуться: попробоватьВернуться, новоеПоколение: новоеПоколение,',
    '  ответУстарел: ответУстарел, поколение: function () { return поколение; } };'
  ].join('\n');

  // Заглушки соседей: комната сохранена, адрес есть, другой вкладки нет.
  const стуки = [];
  const вопросы = [];
  const песочница = {
    Promise: Promise, Boolean: Boolean,
    СПОР_АДРЕСОВ_ЖДЁТ: 1000, СЛОВА_КОМНАТЫ_НЕТ: '',
    опросИдёт: false, код: null, пропуск: null,
    вспомнитьКомнату: function () { return { код: '1234', пропуск: 'п' }; },
    бедаАдреса: function () { return ''; },
    адресСервера: function () { return ДОМЕН; },
    комнатуДержитДругаяВкладка: function () { return false; },
    сказать: function () {}, забытьКомнату: function () {},
    стукВДверь: function () {
      return new Promise(function (готово) { стуки.push(готово); });
    },
    спроситьПроКомнату: function (сохранённое, моё, сказатьЛи, тихо, наИтог) {
      вопросы.push({ моё: моё, тихо: тихо, наИтог: наИтог });
    }
  };
  песочница.globalThis = песочница;
  vm.createContext(песочница);
  vm.runInContext(код, песочница, { filename: 'js/сеть.js (вырезка)' });
  return { дай: песочница.дай, стуки: стуки, вопросы: вопросы };
}

function подождать() { return new Promise(function (г) { setImmediate(г); }); }

async function проверитьПоколения(сеть) {
  let с;
  try { с = собратьПоколения(сеть); }
  catch (сбой) { проверить(false, 'Г вырезка из сеть.js: ' + сбой.message); return; }
  const д = с.дай;

  // Г1. Идёт партия: длинный опрос держит своё поколение. Тихая проверка
  // не должна делать его ответ устаревшим.
  const поколениеОпроса = д.новоеПоколение();
  let итог1 = 'не звали';
  д.попробоватьВернуться(false, true, function (ж) { итог1 = ж; });
  проверить(д.поколение() === поколениеОпроса,
    'Г1 тихая проверка не меняет поколение (было ' + поколениеОпроса + ', стало ' + д.поколение() + ')');
  проверить(!д.ответУстарел(поколениеОпроса),
    'Г1б ответ висящего длинного опроса после тихой проверки не устарел');

  // Г2. Тихая проверка дошла до вопроса о комнате с текущим поколением.
  if (с.стуки.length !== 1) {
    проверить(false, 'Г2 тихая проверка должна была постучать в дверь сервера один раз (стуков: ' + с.стуки.length + ')');
  } else {
    с.стуки[0]({ итог: 'сервер-игры', комнат: 3 });
    await подождать();
    const в = с.вопросы[0];
    проверить(в && в.тихо === true && в.моё === поколениеОпроса,
      'Г2 тихий вопрос о комнате идёт с текущим поколением ' + поколениеОпроса +
      ' (получили ' + JSON.stringify(в ? { моё: в.моё, тихо: в.тихо } : null) + ')');
    if (в) в.наИтог(true);
    проверить(итог1 === true, 'Г2б тихая проверка сообщила итог (получили ' + JSON.stringify(итог1) + ')');
  }

  // Г3. Пока тихая проверка ждала ответа, начался настоящий новый заход —
  // её ответ обязан честно оказаться устаревшим (наИтог(null)).
  let итог3 = 'не звали';
  д.попробоватьВернуться(false, true, function (ж) { итог3 = ж; });
  д.новоеПоколение();
  с.стуки[с.стуки.length - 1]({ итог: 'сервер-игры', комнат: 3 });
  await подождать();
  проверить(итог3 === null, 'Г3 новый заход во время тихой проверки делает её ответ устаревшим (получили ' +
    JSON.stringify(итог3) + ')');

  // Г4. Настоящий возврат (не тихо) по-прежнему заводит новое поколение —
  // заодно доказывает, что песочница вообще видит смену поколения.
  const до = д.поколение();
  д.попробоватьВернуться(true, false, function () {});
  проверить(д.поколение() === до + 1, 'Г4 возврат кнопкой заводит новое поколение (было ' + до +
    ', стало ' + д.поколение() + ')');
}

async function главное() {
  if (доводПапки) console.log('[--папка] файлы берём из ' + ПАПКА);
  const сеть = прочитать('сеть.js');
  проверитьАдреса(сеть, прочитать('рейтинг-экран.js'), прочитать('похвастаться.js'));
  await проверитьПоколения(сеть);

  const провалы = проверки.filter(function (п) { return !п.ок; });
  console.log('Адрес сервера без хвоста и тихая проверка живости:');
  for (const п of проверки) console.log((п.ок ? '  ok   ' : '  ПРОВАЛ ') + п.текст);
  console.log('Итого проверок: ' + проверки.length + ', провалов: ' + провалы.length);
  process.exit(провалы.length ? 1 : 0);
}

главное().catch(function (сбой) {
  console.error('Проверка упала: ' + (сбой && сбой.stack || сбой));
  process.exit(1);
});
