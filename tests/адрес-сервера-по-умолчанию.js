/* =====================================================================
   АДРЕС СЕРВЕРА БЕЗ ХВОСТА И ТИХАЯ ПРОВЕРКА ЖИВОСТИ — переезд на свой домен.

   Игра переезжает на https://igra.medart.com.ua: nginx отдаёт и страницы,
   и API сервера комнат с одного адреса. Поэтому страница без «?сервер=»
   должна искать сервер там же, откуда пришла (location.origin). Исключения:
     - свой компьютер (localhost, 127.0.0.1, файл с диска) — сервер
       разработки на http://127.0.0.1:8790, как раньше;
     - GitHub Pages (*.github.io) — сервера там нет, адреса нет ('').
   Хвост ссылки «?сервер=» / «?server=» главнее всего, на любом хосте.

   Второе, что проверяем, — «замерзание» партии. Тихая проверка живости
   комнаты (раз в 20 с, плашка «Вернуться к игре») раньше заводила новое
   поколение, и висящий длинный опрос считал свой ответ устаревшим: ходы
   соперника переставали приходить. Проверяем поведение настоящего кода:
   функции «попробоватьВернуться», «новоеПоколение», «ответУстарел»
   вырезаются из js/сеть.js и запускаются в песочнице с заглушками соседей.

   Запуск:          node tests/адрес-сервера-по-умолчанию.js
   Ломающий запуск: node tests/адрес-сервера-по-умолчанию.js --папка=<путь>
     — берёт сеть.js, рейтинг-экран.js, похвастаться.js не из js/ проекта,
       а из указанной папки (копия во временной папке, вне проекта; её
       портит тот, кто запускает). С испорченной копией обязано краснеть.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { поднять, сделатьДокумент, сделатьПамять } = require('./поддельный-браузер.js');

const КОРЕНЬ = path.join(__dirname, '..');
const доводПапки = process.argv.find(function (д) { return д.indexOf('--папка=') === 0; });
const ПАПКА = доводПапки ? path.resolve(доводПапки.slice('--папка='.length)) : path.join(КОРЕНЬ, 'js');

const ДОМЕН = 'https://igra.medart.com.ua';
const РАЗРАБОТКА = 'http://127.0.0.1:8790';
const ХВОСТ = 'https://мой-туннель.example';

const проверки = [];
function проверить(условие, текст) { проверки.push({ ок: Boolean(условие), текст: текст }); }

function прочитать(имя) {
  return fs.readFileSync(path.join(ПАПКА, имя), 'utf8');
}

function место(протокол, хост, origin, поиск) {
  return { href: origin + '/' + (поиск || ''), search: поиск || '', hash: '', pathname: '/',
    origin: origin, protocol: протокол, host: хост };
}

/* Все места, на которых сверяем адрес, и чего от них ждём. */
