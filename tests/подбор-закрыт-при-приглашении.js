/* ---------------- Подпись Telegram — по правилу сервера ---------------- */

function подписать(поля) {
  const строки = Object.keys(поля).map(function (к) { return к + '=' + поля[к]; }).sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(ТОКЕН).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}

function подпись(номер, имя) {
  const поля = {
    query_id: 'AAZ' + номер,
    user: JSON.stringify({ id: номер, first_name: имя }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  поля.hash = подписать(поля);
  return Object.keys(поля)
    .map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(поля[к]); })
    .join('&');
}

/* ---------------- Разговор с дверями ---------------- */

function спросить(путь, тело) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: АДРЕС, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (сбой) { разобрано = null; }
        готово({ код: ответ.statusCode, тело: разобрано || {}, текст: текст });
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

function ссылкаЗаСтол(метка, код) {
  return 'https://t.me/' + ИМЯ_БОТА + '/BoardGames?startapp=' + (метка ? метка + '_' : '') + код + '-' + АДРЕС_БУКВАМИ;
}

async function создатьОткрытыйСтол(кто, имя, игра) {
  const ответ = await спросить('/создать', {
    initData: подпись(кто, имя), имя: имя, метка: 'metka-zakryt-' + кто, игра: игра, открытый: true
  });
  if (ответ.код !== 200 || !ответ.тело.код) throw new Error('стол для ' + имя + ' не создан: ' + ответ.текст);
  return { код: ответ.тело.код, пропуск: ответ.тело.пропуск, кто: кто, имя: имя };
}

async function видХозяина(стол) {
  const ответ = await спросить('/состояние', { код: стол.код, пропуск: стол.пропуск });
  return ответ.тело.состояние || {};
}

function искать(кто, имя, игра) {
  return спросить('/подбор', { initData: подпись(кто, имя), игра: игра });
}

function отменить(ответ) {
  if (!ответ || !ответ.тело || !ответ.тело.ключОжидания) return Promise.resolve();
  return спросить('/подбор-отмена', { ключОжидания: ответ.тело.ключОжидания });
}

function позвать(стол, метка) {
  return спросить('/приглашение', { initData: подпись(стол.кто, стол.имя), ссылка: ссылкаЗаСтол(метка, стол.код) });
}

function войтиДругом(стол, кто, имя, номер) {
  return спросить('/войти', {
    код: стол.код, имя: имя, метка: 'metka-zakryt-' + кто, initData: подпись(кто, имя), приглашение: номер
  });
}

function людей(стол) {
  return комнаты.состояниеСтола(стол.код).людей;
}

/* ---------------- Пункты ---------------- */

async function контрольБезПриглашения() {
  console.log('а) Контроль: без приглашения искатель садится за открытый стол');
  const стол = await создатьОткрытыйСтол(701, 'Аня', 'дурак');
  проверить((await видХозяина(стол)).открытыйСтол === true, 'а: хозяйка видит «подбор включён»');
  const боря = await искать(702, 'Боря', 'дурак');
  проверить(боря.тело.статус === 'свели' && боря.тело.код === стол.код, 'а: Боря посажен за открытый стол Ани');
  проверить(людей(стол) === 2, 'а: за столом Ани двое');
}

/* Общее для дурака и шашек: зов закрывает подбор, друг садится. */
async function зовЗакрываетПодбор(буква, игра, метка, номера) {
  const стол = await создатьОткрытыйСтол(номера[0], 'Хозяин' + номера[0], игра);
  const до = await видХозяина(стол);
  проверить(до.открытыйСтол === true, буква + ': до зова подбор у хозяина включён');

  // Хозяин держит длинный опрос, как настоящая страница: он обязан проснуться.
  const опрос = спросить('/что-нового', { код: стол.код, пропуск: стол.пропуск, версия: до.версия });

  const зов = await позвать(стол, метка);
  const номер = зов.тело.приглашение || '';
  проверить(зов.тело.ок === true && /^[a-z0-9]{8}$/.test(номер),
    буква + ': приглашение заведено с номером (' + зов.текст.slice(0, 120) + ')');

  const новости = await опрос;
  проверить(новости.тело.изменилось === true && новости.тело.состояние &&
    новости.тело.состояние.открытыйСтол === false,
    буква + ': опрос хозяина проснулся с «открытыйСтол: false» — переключатель выключен');
  проверить((await видХозяина(стол)).открытыйСтол === false, буква + ': /состояние хозяина — подбор выключен');
  const вСписке = комнаты.открытыеСтолы(игра).some(function (с) { return с.код === стол.код; }) ||
    JSON.stringify(комнаты.открытыеСтолы(игра)).indexOf(стол.код) !== -1;
  проверить(!вСписке, буква + ': стола нет и в списке открытых');

  const искатель = await искать(номера[1], 'Искатель' + номера[1], игра);
  проверить(искатель.тело.статус === 'ждёт', буква + ': искатель «Найти игру» НЕ сел — ждёт в очереди');
  проверить(искатель.тело.код !== стол.код, буква + ': искателю не отдан код стола хозяина');
  проверить(людей(стол) === 1, буква + ': за столом по-прежнему один хозяин');
  await отменить(искатель);

  const друг = await войтиДругом(стол, номера[2], 'Друг' + номера[2], номер);
  проверить(друг.код === 200 && Boolean(друг.тело.пропуск), буква + ': друг по ссылке с номером сел (' + друг.текст.slice(0, 120) + ')');
  проверить(людей(стол) === 2, буква + ': за столом хозяин и друг');
  return стол;
}

async function хозяинСноваВключил() {
  console.log('в) Хозяин после зова сам снова включил подбор — включается');
  const стол = await создатьОткрытыйСтол(721, 'Вера', 'дурак');
  const зов = await позвать(стол, '');
  проверить(зов.тело.ок === true, 'в: приглашение заведено');
  проверить((await видХозяина(стол)).открытыйСтол === false, 'в: после зова подбор выключен');
  const включила = await спросить('/ход', { код: стол.код, пропуск: стол.пропуск, действие: 'открыть-стол', открыть: true });
  проверить(включила.тело.принято === true, 'в: сервер принял «открыть подбор» от хозяйки');
  проверить((await видХозяина(стол)).открытыйСтол === true, 'в: подбор снова включён');
  const гоша = await искать(722, 'Гоша', 'дурак');
  проверить(гоша.тело.статус === 'свели' && гоша.тело.код === стол.код, 'в: теперь искатель садится за стол Веры');
}

async function зовЗнакомогоЗакрываетПодбор() {
  console.log('д) «Позвать знакомого» (/позвать) закрывает подбор');
  const стол = await создатьОткрытыйСтол(741, 'Дина', 'дурак');
  // Знакомство — будто вчера сыграли вместе; ключ знакомого берём из /знакомые, как игра.
  знакомые.запомнитьЗастолье([{ номер: 741, имя: 'Дина' }, { номер: 743, имя: 'Жора' }], 'дурак');
  const список = await спросить('/знакомые', { initData: подпись(741, 'Дина') });
  const жора = ((список.тело && список.тело.знакомые) || []).find(function (з) { return з.имя === 'Жора'; });
  проверить(Boolean(жора && жора.ключ), 'д: у хозяйки есть знакомый Жора с ключом для зова');
  проверить((await видХозяина(стол)).открытыйСтол === true, 'д: до зова подбор включён');

  const зов = await спросить('/позвать', {
    initData: подпись(741, 'Дина'), ключ: жора ? жора.ключ : '', ссылка: ссылкаЗаСтол('', стол.код), код: стол.код
  });
  проверить(зов.тело.ок === true, 'д: письмо знакомому ушло (' + зов.текст.slice(0, 120) + ')');
  проверить((await видХозяина(стол)).открытыйСтол === false, 'д: после зова знакомого подбор выключен');

  const искатель = await искать(742, 'Искатель742', 'дурак');
  проверить(искатель.тело.статус === 'ждёт', 'д: искатель «Найти игру» НЕ сел — ждёт в очереди');
  проверить(людей(стол) === 1, 'д: за столом по-прежнему одна хозяйка');
  await отменить(искатель);

  const вход = await спросить('/войти', { код: стол.код, имя: 'Жора', метка: 'metka-zakryt-743', initData: подпись(743, 'Жора') });
  проверить(вход.код === 200 && Boolean(вход.тело.пропуск), 'д: знакомый по коду из письма сел (' + вход.текст.slice(0, 120) + ')');
  проверить(людей(стол) === 2, 'д: за столом хозяйка и знакомый');
}

