/* =====================================================================
   СЕТЬ, ПАРАМИ, С ВЫБЫВАНИЕМ — проверка сетевого стола 2 на 2 в тот
   самый миг, ради которого всё и затевалось: кто-то остался без карт,
   а партия продолжается втроём.

   ЧТО ИМЕННО ПРОВЕРЯЕТСЯ. Сервер и браузер должны одинаково понимать,
   с какого МЕСТА сейчас нападают. Раньше браузер угадывал это перебором:
   искал место, при котором отбивался бы названный сервером защитник.
   Пока у каждого было по одному месту, ответ был единственным. После
   выбывания одиночка играет за ДВА места, перебор стал неоднозначным —
   и сервер теперь присылает номер кресла атакующего прямо («креслоАтаки»).

   Проверка спрашивает у сервера три вещи и сверяет их между собой:
     1) «креслоАтаки» — с какого кресла нападают;
     2) список мест «застолом» — кто ходит, кто отбивается, кто выбыл
        и кто играет за опустевшее место («заНегоИграет»);
     3) «яХожу» у каждого живого — не бросили ли кого-то зрителем.

   Правила при этом считаются здесь заново, своими руками, по словам:
   место выбывшего не пустует, за него играет напарник; отбивается
   следующее занятое место по кругу.

   Отдельно смотрим за руками: в ответе игроку не должно быть ни одной
   чужой карты — только числа.

   ЗАПУСК (сервер комнат уже поднят):
       node tests/сеть-парами-с-выбыванием.js            порт 8790, 8 партий
       node tests/сеть-парами-с-выбыванием.js 8790 20
   ===================================================================== */

const http = require('http');
const path = require('path');
const правила = require(path.join(__dirname, '..', 'js', 'game.js'));

const ПОРТ = Number(process.argv[2]) || 8790;
const ПАРТИЙ = Number(process.argv[3]) || 8;
const ХОСТ = '127.0.0.1';
const ПОТОЛОК_ДЕЙСТВИЙ = 1200;
/* Сколько кругов подряд ждём, если ничего не происходит. Боты ходят
   на сервере сами и не мгновенно — примерно раз в 0,7 секунды на ход.
   Поэтому между пустыми кругами мы ещё и спим: без сна проверка
   пролетала «терпение» за доли секунды и объявляла зависшей партию,
   в которой просто думал бот. */
const ТЕРПЕНИЕ = 150;
const пауза = function (мс) { return new Promise(function (г) { setTimeout(г, мс); }); };

const беды = [];
const замер = {
  партий: 0,
  доиграно: 0,
  сВыбыванием: 0,
  подходовПослеВыбывания: 0,
  креслоСошлось: 0,
  ходовУКаждого: {},
  чужихКартВОтвете: 0,
  проверок: 0
};

function пожаловаться(что, подробности) {
  const строка = что + (подробности ? ' — ' + подробности : '');
  if (беды.indexOf(строка) === -1) беды.push(строка);
}

function запрос(путь, тело) {
  return new Promise(function (готово) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const req = http.request({
      host: ХОСТ, port: ПОРТ, method: 'POST', path: encodeURI(путь),
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let куски = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (к) { куски += к; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(куски); } catch (е) { разобрано = { разбор: 'не JSON', сырое: куски }; }
        готово({ номер: ответ.statusCode, данные: разобрано });
      });
    });
    req.on('error', function (е) { готово({ номер: 0, данные: { ошибка: String(е.message) } }); });
    req.write(данные);
    req.end();
  });
}

function жив() {
  return new Promise(function (готово) {
    http.get({ host: ХОСТ, port: ПОРТ, path: encodeURI('/здоровье') }, function (о) {
      о.resume();
      готово(о.statusCode === 200);
    }).on('error', function () { готово(false); });
  });
}

/** Один живой игрок за сетевым столом. */
class Игрок {
  constructor(имя, код, пропуск, состояние) {
    this.имя = имя;
    this.код = код;
    this.пропуск = пропуск;
    this.вид = состояние || null;
  }
  async обновить() {
    const ответ = await запрос('/состояние', { код: this.код, пропуск: this.пропуск });
    if (ответ.номер === 200 && ответ.данные && ответ.данные.состояние) {
      this.вид = ответ.данные.состояние;
    }
    return this.вид;
  }
  async ход(что) {
    const тело = Object.assign({ код: this.код, пропуск: this.пропуск }, что);
    const ответ = await запрос('/ход', тело);
    if (ответ.номер === 200 && ответ.данные) {
      if (ответ.данные.состояние) this.вид = ответ.данные.состояние;
      return ответ.данные;
    }
    return null;
  }
}

/* --------------------------------------------------------------------
   Свой счёт правил — по словам, а не по коду игры.
   -------------------------------------------------------------------- */

/** Кто играет за это кресло: сам сидящий, а если он вышел — его напарник. */
function ктоЗаКреслом(места, номер) {
  const место = места.filter(function (м) { return м.номер === номер; })[0];
  if (!место) return null;
  if (!место.выбыл) return место.номер;
  const нап = место.напарник;
  if (!нап) return null;
  const напМесто = места.filter(function (м) { return м.номер === нап; })[0];
  return напМесто && !напМесто.выбыл ? напМесто.номер : null;
}

/** Свои ли эти два кресла (сам себе свой, напарник тоже свой). */
function своиКресла(места, одно, другое) {
  if (одно === другое) return true;
  const м = места.filter(function (м2) { return м2.номер === одно; })[0];
  return Boolean(м && м.напарник === другое);
}

/** С какого кресла отбиваются, если нападают с названного. */
function креслоЗащиты(места, креслоАтаки) {
  const порядок = места.map(function (м) { return м.номер; }).sort(function (а, б) { return а - б; });
  const где = порядок.indexOf(креслоАтаки);
  if (где === -1) return null;
  const ктоНападает = ктоЗаКреслом(места, креслоАтаки);
  for (let шаг = 1; шаг < порядок.length; шаг++) {
    const кресло = порядок[(где + шаг) % порядок.length];
    const кто = ктоЗаКреслом(места, кресло);
    if (!кто) continue;
    if (ктоНападает && своиКресла(места, ктоНападает, кто)) continue;
    return кресло;
  }
  return креслоАтаки;
}

/* --------------------------------------------------------------------
   Сверка одного ответа сервера.
   -------------------------------------------------------------------- */

function проверитьВид(вид, чей) {
  if (!вид || !Array.isArray(вид.застолом)) return;
  замер.проверок++;
  const места = вид.застолом;

  // Чужих карт в ответе быть не должно ни одной.
  for (const м of места) {
    if (м.этоЯ) continue;
    if (Array.isArray(м.рука) || Array.isArray(м.карты)) {
      замер.чужихКартВОтвете++;
      пожаловаться('в ответе сервера видны ЧУЖИЕ карты', 'кресло ' + м.номер + ', игрок ' + чей);
    }
  }

  if (вид.завершена) return;

  // Кресло атаки обязано прийти от сервера — браузер его больше не угадывает.
  if (typeof вид.креслоАтаки !== 'number') {
    пожаловаться('сервер не прислал номер кресла атакующего', 'игрок ' + чей +
      ', пришло: ' + JSON.stringify(вид.креслоАтаки));
    return;
  }

  // С этого кресла обязан кто-то играть.
  const нападающий = ктоЗаКреслом(места, вид.креслоАтаки);
  if (!нападающий) {
    пожаловаться('нападают с кресла, за которым никого нет',
      'кресло ' + вид.креслоАтаки + ' (игрок ' + чей + ')');
    return;
  }

  // Защитник по нашему счёту обязан совпасть с тем, кого назвал сервер.
  const моёКреслоЗащиты = креслоЗащиты(места, вид.креслоАтаки);
  const защитникСервера = места.filter(function (м) { return м.отбивается; })[0];
  if (защитникСервера) {
    const ктоДолжен = ктоЗаКреслом(места, моёКреслоЗащиты);
    if (ктоДолжен !== защитникСервера.номер) {
      пожаловаться('сервер и правила разошлись, кто отбивается',
        'нападают с кресла ' + вид.креслоАтаки + ', сервер назвал защитником кресло ' +
        защитникСервера.номер + ', а по правилам отбивается кресло ' + ктоДолжен +
        ' (вышли: ' + места.filter(function (м) { return м.выбыл; })
          .map(function (м) { return м.номер; }).join(',') + ')');
    } else {
      замер.креслоСошлось++;
    }
  }

  // Надпись «за него играет» — только у выбывшего и только на живого напарника.
  for (const м of места) {
    if (!м.выбыл) {
      if (м.заНегоИграет) {
        пожаловаться('сервер написал «за него играет» про живого игрока', 'кресло ' + м.номер);
      }
      continue;
    }
    const ктоДолжен = ктоЗаКреслом(места, м.номер);
    const ответСервера = м.заНегоИграет || null;
    const ожидание = ктоДолжен === м.номер ? null : ктоДолжен;
    if ((ответСервера || null) !== (ожидание || null)) {
      пожаловаться('сервер неверно сказал, кто играет за опустевшее кресло',
        'кресло ' + м.номер + ': сервер — ' + JSON.stringify(ответСервера) +
        ', по правилам — ' + JSON.stringify(ожидание));
    }
  }
}

/* --------------------------------------------------------------------
   Простой игрок: кроет чем может, иначе берёт; ходит первой годной картой.
   -------------------------------------------------------------------- */

async function походить(игрок) {
  const вид = игрок.вид;
  if (!вид || вид.завершена) return false;

  if (вид.фаза === 'защита') {
    if (вид.могуПеревести) {
      for (let к = 0; к < вид.мояРука.length; к++) {
        const ответ = await игрок.ход({ действие: 'перевести', карта: к });
        if (ответ && ответ.принято) return true;
      }
    }
    for (let п = 0; п < вид.стол.length; п++) {
      if (вид.стол[п].защита) continue;
      for (let к = 0; к < вид.мояРука.length; к++) {
        if (!правила.бьёт(вид.мояРука[к], вид.стол[п].атака, вид.козырь)) continue;
        const ответ = await игрок.ход({ действие: 'отбить', пара: п, карта: к });
        if (ответ && ответ.принято) return true;
      }
    }
    const беру = await игрок.ход({ действие: 'беру' });
    return Boolean(беру && беру.принято);
  }

  for (let к = 0; к < вид.мояРука.length; к++) {
    const ответ = await игрок.ход({ действие: 'ходить', карта: к });
    if (ответ && ответ.принято) return true;
  }
  const бито = await игрок.ход({ действие: 'бито' });
  return Boolean(бито && бито.принято);
}

/* --------------------------------------------------------------------
   Одна партия: стол на четверых парами, двое живых и два бота.
   Живых берём двоих, чтобы за одним столом были и «я», и настоящий
   второй игрок: их ответы должны говорить об одном и том же.
   -------------------------------------------------------------------- */

async function сыгратьПартию(номер) {
  const создание = await запрос('/создать', { мест: 4, парами: true, переводной: номер % 2 === 0, имя: 'Первый' });
  if (создание.номер !== 200 || !создание.данные.код) {
    пожаловаться('сервер не создал комнату парами', 'код ответа ' + создание.номер);
    return;
  }
  const код = создание.данные.код;
  const игроки = [new Игрок('Первый', код, создание.данные.пропуск, создание.данные.состояние)];

  const вход = await запрос('/войти', { код: код, имя: 'Второй' });
  if (вход.номер !== 200 || !вход.данные.пропуск) {
    пожаловаться('второй живой не смог войти по коду', 'код ответа ' + вход.номер);
    return;
  }
  игроки.push(new Игрок('Второй', код, вход.данные.пропуск, вход.данные.состояние));

  for (let н = 2; н < 4; н++) {
    const ответ = await игроки[0].ход({ действие: 'бот' });
    if (!ответ || !ответ.принято) {
      пожаловаться('хозяин не смог посадить бота за парный стол',
        'место ' + (н + 1) + ((ответ && ответ.причина) ? ': ' + ответ.причина : ''));
      return;
    }
  }

  const пуск = await игроки[0].ход({ действие: 'начать' });
  if (!пуск || !пуск.принято) {
    пожаловаться('парная партия по сети не началась',
      (пуск && пуск.причина) ? пуск.причина : 'сервер промолчал');
    return;
  }
  for (const и of игроки) await и.обновить();
  замер.партий++;

  let действий = 0;
  let тишины = 0;
  let былоВыбывание = false;
  let прошлаяВерсия = игроки[0].вид ? игроки[0].вид.версия : null;
  const ходилиПослеВыбывания = {};   // номер кресла → сколько раз ходил
  let прошлоеКресло = null;

  while (!игроки[0].вид.завершена && действий < ПОТОЛОК_ДЕЙСТВИЙ && тишины < ТЕРПЕНИЕ) {
    let сделали = false;
    for (const и of игроки) {
      проверитьВид(и.вид, и.имя);
      if (и.вид && и.вид.яХожу && !и.вид.завершена) {
        if (await походить(и)) { сделали = true; действий++; }
      }
    }
    for (const и of игроки) await и.обновить();

    const вид = игроки[0].вид;
    if (вид && Array.isArray(вид.застолом)) {
      const выбывшие = вид.застолом.filter(function (м) { return м.выбыл; });
      if (выбывшие.length) {
        if (!былоВыбывание) { былоВыбывание = true; замер.сВыбыванием++; }
        // Новый подход виден по смене кресла атаки.
        if (вид.креслоАтаки !== прошлоеКресло) {
          прошлоеКресло = вид.креслоАтаки;
          замер.подходовПослеВыбывания++;
          ходилиПослеВыбывания[вид.креслоАтаки] = (ходилиПослеВыбывания[вид.креслоАтаки] || 0) + 1;
          замер.ходовУКаждого[вид.креслоАтаки] = (замер.ходовУКаждого[вид.креслоАтаки] || 0) + 1;
        }
      }
    }

    const версия = вид ? вид.версия : null;
    if (!сделали && версия === прошлаяВерсия) тишины++; else тишины = 0;
    прошлаяВерсия = версия;
    if (!сделали) await пауза(120);   // даём боту на сервере походить
  }

  if (игроки[0].вид.завершена) замер.доиграно++;
  else pпожалуйстаЗастряла(игроки, действий, тишины);

  // Если после выбывания подходов было достаточно, нападать обязаны с разных кресел:
  // одиночка играет за два места, и оба обязаны попадать в круг.
  const кресла = Object.keys(ходилиПослеВыбывания);
  if (замер.подходовПослеВыбывания >= 6 && кресла.length === 1) {
    пожаловаться('после выбывания нападают всегда с одного кресла',
      'кресло ' + кресла[0] + ', подходов ' + ходилиПослеВыбывания[кресла[0]]);
  }

  await игроки[0].ход({ действие: 'выйти' });
  await игроки[1].ход({ действие: 'выйти' });
}

function pпожалуйстаЗастряла(игроки, действий, тишины) {
  const вид = игроки[0].вид || {};
  пожаловаться('партия по сети не доигралась',
    'действий ' + действий + ', тишины подряд ' + тишины + ', фаза ' + вид.фаза +
    ', кресло атаки ' + вид.креслоАтаки +
    ', за столом: ' + (вид.застолом || []).map(function (м) {
      return '№' + м.номер + (м.выбыл ? '(вышел)' : '') + ':' + м.карт;
    }).join(' '));
}

async function главное() {
  console.log('=== Сеть, парами, с выбыванием ===');
  console.log('сервер: http://' + ХОСТ + ':' + ПОРТ + ', партий: ' + ПАРТИЙ);
  if (!(await жив())) {
    console.error('Сервер комнат не отвечает на http://' + ХОСТ + ':' + ПОРТ + '/здоровье');
    console.error('Запустите его: node server/сервер.js ' + ПОРТ);
    process.exit(2);
  }
  for (let н = 1; н <= ПАРТИЙ; н++) await сыгратьПартию(н);

  console.log('партий начато: ' + замер.партий + ', доиграно до конца: ' + замер.доиграно);
  console.log('партий, где кто-то вышел без карт: ' + замер.сВыбыванием +
    ', подходов после выбывания: ' + замер.подходовПослеВыбывания);
  console.log('с каких кресел нападали после выбывания: ' +
    JSON.stringify(замер.ходовУКаждого));
  console.log('сверок «кто отбивается» сошлось: ' + замер.креслоСошлось +
    ' (всего осмотрено ответов сервера: ' + замер.проверок + ')');
  console.log('чужих карт в ответах: ' + замер.чужихКартВОтвете);

  if (беды.length) {
    console.log('\nНАЙДЕНО (' + беды.length + '):');
    беды.slice(0, 20).forEach(function (б) { console.log('  - ' + б); });
    process.exit(1);
  }
  console.log('\n=== Итог: сетевой парный стол считает очередь так же, как правила ===');
}

главное();
