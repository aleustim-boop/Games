let номерАдреса = 0;
const ИМЕНА = ['Аня', 'Боря', 'Вера', 'Гриша'];

/**
 * Стол дурака на 4 человек. Возвращает комнату, код и людей в порядке
 * мест партии: [{ место, номер }, ...].
 */
function собратьСтол(телеграмС, парами, мест) {
  номерАдреса++;
  const сколько = мест || 4;
  const настройки = { имя: ИМЕНА[0], телеграм: телеграмС, игра: 'дурак', мест: сколько };
  if (парами) настройки.парами = true;
  const создана = комнаты.создатьКомнату('10.8.0.' + номерАдреса, настройки);
  if (!создана.ок) throw new Error('комната не создалась: ' + создана.причина);
  const хозяин = комнаты.найтиИгрока(создана.код, создана.пропуск);
  const номерМеста = {};
  номерМеста[хозяин.ктоЯ] = телеграмС;
  for (let i = 1; i < сколько; i++) {
    const вход = комнаты.войтиВКомнату(создана.код, { имя: ИМЕНА[i], телеграм: телеграмС + i });
    if (!вход.ок) throw new Error(ИМЕНА[i] + ' не вошёл: ' + вход.причина);
    номерМеста[комнаты.найтиИгрока(создана.код, вход.пропуск).ктоЯ] = телеграмС + i;
  }
  const комната = хозяин.комната;
  if (комната.этап === 'ожидание') {
    const начали = комнаты.сделатьХод(комната, хозяин.ктоЯ, { действие: 'начать' });
    if (!начали.принято) throw new Error('партия не началась: ' + начали.причина);
  }
  const люди = комната.партия.игроки.map(function (место) {
    return { место: место, номер: номерМеста[место] };
  });
  return { комната: комната, код: создана.код, люди: люди };
}

/**
 * Раскладка «A уже вне игры»: колода кончилась, у A пустая рука, A в
 * списке выбывших (так правила дурака отмечают скинувшего карты при
 * пустой колоде). A — место 4-е по кругу: не нападает и не отбивается,
 * чтобы раскладка не встала поперёк идущего хода. Карты A и колода
 * уходят в отбой. Остальные трое помечены сходившими — уход любого из
 * них будет сдачей, а не отменой партии.
 * Ответ: { A, B, C, D } — { место, номер } в порядке мест 4, 1, 2, 3.
 */
function AВнеИгры(стол) {
  const п = стол.комната.партия;
  const [первый, второй, третий, четвёртый] = стол.люди;
  const A = четвёртый;
  п.отбой = п.отбой.concat(п.руки[A.место], п.колода);
  п.руки[A.место] = [];
  п.колода = [];
  п.выбывшие = [A.место];
  for (const кто of [первый, второй, третий]) стол.комната.игроки[кто.место].ходовВПартии = 1;
  return { A: A, B: первый, C: второй, D: третий };
}

function предложить(комната, кто) {
  return комнаты.сделатьХод(комната, кто.место, { действие: 'закончить-предложить' });
}
function заГолос(комната, кто) {
  return комнаты.сделатьХод(комната, кто.место, { действие: 'закончить-голос', за: true });
}

/** Голосовать «за» по очереди, пока партия не кончится. */
function всеЗа(комната, кто) {
  предложить(комната, кто[0]);
  for (let i = 1; i < кто.length && комната.этап === 'игра'; i++) заГолос(комната, кто[i]);
  return комната.этап === 'конец' && комната.партия.завершена === true &&
         комната.партия.законченаПоСогласию === true;
}

function записьЗастолья(вызов, номер) {
  return вызов ? вызов.застолье.find(function (з) { return з.номер === номер; }) : null;
}

/** Общая проверка «A победил без очков, B, C, D вне счёта» — случаи (а) и (в). */
function AПобедилБезОчков(стол, роли, вызовДо) {
  const к = стол.комната;
  const { A, B, C, D } = роли;
  проверить(Array.isArray(к.партия.победителиПоСогласию) &&
            к.партия.победителиПоСогласию.length === 1 && к.партия.победителиПоСогласию[0] === A.место,
            'победителиПоСогласию — ровно A: ' + JSON.stringify(к.партия.победителиПоСогласию));
  проверить(Array.isArray(к.партия.проигравшие) && к.партия.проигравшие.length === 0, 'проигравших нет');
  проверить(вызовыРейтинга.length === вызовДо + 1, 'рейтинг зван один раз (сдавшихся нет, но победитель есть)');
  const вызов = вызовыРейтинга[вызовДо];
  const зA = записьЗастолья(вызов, A.номер);
  проверить(Boolean(зA) && зA.победил === true && зA.внеСчёта === false && зA.этоБот === false,
            'A в застолье: победил, в счёте, человек — ' + JSON.stringify(зA && { победил: зA.победил, внеСчёта: зA.внеСчёта, этоБот: зA.этоБот }));
  for (const [имя, кто] of [['B', B], ['C', C], ['D', D]]) {
    const з = записьЗастолья(вызов, кто.номер);
    проверить(Boolean(з) && з.внеСчёта === true && з.победил === false, имя + ' в застолье вне счёта, без победы');
  }
  const рA = строкаРейтинга(A.номер);
  проверить(Boolean(рA) && рA.партий === 1 && рA.побед === 1 && рA.очки === 0,
            'A в рейтинге: партий 1, побед 1, очков 0 — ' + JSON.stringify(рA));
  for (const [имя, кто] of [['B', B], ['C', C], ['D', D]]) {
    проверить(строкаРейтинга(кто.номер) === null, имя + ': записи в рейтинге нет');
  }
}

