function случайА() {
  console.log('\nа) A скинул карты, все «за» — победа A без очков, остальные вне счёта');
  const стол = собратьСтол(71001, false);
  const роли = AВнеИгры(стол);
  const к = стол.комната;
  const вызовДо = вызовыРейтинга.length;
  проверить(всеЗа(к, [роли.B, роли.C, роли.D, роли.A]), 'партия закончена по согласию');
  проверить(к.партия.результат === null, 'результат пустой (сдавшихся нет)');
  AПобедилБезОчков(стол, роли, вызовДо);
  комнаты.удалитьКомнату(стол.код);
}

function случайБ() {
  console.log('\nб) B сдался уходом, потом согласие — у A очки только за B, у B поражение');
  const стол = собратьСтол(72001, false);
  const { A, B, C, D } = AВнеИгры(стол);
  const к = стол.комната;
  комнаты.выйти(к, B.место);
  проверить(к.игроки[B.место].сдался === true, 'B ушёл и «сдался»');
  проверить(к.этап === 'игра', 'партия идёт после ухода B');
  const вызовДо = вызовыРейтинга.length;
  проверить(всеЗа(к, [C, D, A]), 'партия закончена по согласию');
  проверить(JSON.stringify(к.партия.победителиПоСогласию) === JSON.stringify([A.место]),
            'победителиПоСогласию — ровно A');
  проверить(JSON.stringify(к.партия.проигравшие) === JSON.stringify([B.место]), 'проигравший — ровно B');
  проверить(вызовыРейтинга.length === вызовДо + 1, 'рейтинг зван один раз');
  const вызов = вызовыРейтинга[вызовДо];
  const зA = записьЗастолья(вызов, A.номер);
  const зB = записьЗастолья(вызов, B.номер);
  проверить(Boolean(зA) && зA.победил === true && зA.внеСчёта === false, 'A в застолье победил и в счёте');
  проверить(Boolean(зB) && зB.победил === false && зB.внеСчёта === false && зB.этоБот === false,
            'B в застолье: поражение, в счёте, человек');
  for (const [имя, кто] of [['C', C], ['D', D]]) {
    const з = записьЗастолья(вызов, кто.номер);
    проверить(Boolean(з) && з.внеСчёта === true && з.победил === false, имя + ' в застолье вне счёта');
  }
  const рA = строкаРейтинга(A.номер);
  проверить(Boolean(рA) && рA.партий === 1 && рA.побед === 1 && рA.очки === ЗА_ЧЕЛОВЕКА,
            'A в рейтинге: побед 1, очки только за B (' + ЗА_ЧЕЛОВЕКА + ') — ' + JSON.stringify(рA));
  const рB = строкаРейтинга(B.номер);
  проверить(Boolean(рB) && рB.партий === 1 && рB.побед === 0, 'B в рейтинге: партия 1, побед 0 — ' + JSON.stringify(рB));
  проверить(строкаРейтинга(C.номер) === null && строкаРейтинга(D.номер) === null, 'C и D: записи в рейтинге нет');
  комнаты.удалитьКомнату(стол.код);
}

