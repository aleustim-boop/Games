/* Файл может лежать с концами строк Windows (\r\n): многострочный кусок
   порчи тогда ищем и вставляем в том же виде, иначе он не найдётся. */
function какВФайле(текст, кусок) {
  return текст.indexOf('\r\n') !== -1 ? кусок.replace(/\r?\n/g, '\r\n') : кусок;
}

function сколькоРаз(текст, кусок) {
  return текст.split(какВФайле(текст, кусок)).length - 1;
}

