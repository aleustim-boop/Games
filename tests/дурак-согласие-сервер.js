/**
 * Раскладка «осталось сказать „бито“»: колода пуста, на столе одна отбитая
 * пара, все подкидывающие, кроме «закрывает», уже спасовали. У «выйдет»
 * рука пуста — когда подход закроют, он выйдет из игры (так правила
 * отмечают выбывших: только в конце подхода). Карты стола берём того
 * достоинства, которого нет у закрывающего: иначе бот подкинул бы,
 * а не сказал «бито». Нападает «закрывает».
 */
function раскладкаБито(стол, выйдет, закрывает) {
  const п = стол.комната.партия;
  п.отбой = п.отбой.concat(п.колода, п.руки[выйдет.место]);
  п.колода = [];
  п.руки[выйдет.место] = [];
  п.выбывшие = [];
  п.атакует = закрывает.место;
  п.местоАтаки = п.игроки.indexOf(закрывает.место);
  const заняты = (п.руки[закрывает.место] || []).map(function (к) { return к.имя; });
  const годные = п.отбой.filter(function (к) { return заняты.indexOf(к.имя) === -1; });
  if (годные.length < 2) throw new Error('не нашлось карт для стола');
  const атака = годные[0];
  const защита = годные.find(function (к) { return к.имя === атака.имя && к !== атака; }) || годные[1];
  п.отбой = п.отбой.filter(function (к) { return к !== атака && к !== защита; });
  п.стол = [{ атака: атака, защита: защита }];
  п.берёт = false;
  п.пасы = стол.люди.map(function (м) { return м.место; }).filter(function (место) {
    return место !== закрывает.место;
  });
  for (const м of стол.люди) стол.комната.игроки[м.место].ходовВПартии = 1;
}

