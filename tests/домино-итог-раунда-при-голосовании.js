'use strict';
/* Домино: окно итогов раунда и голосование «закончить партию по согласию».
   Беда, которую чиним: окно итогов открыто поверх всего, а плашку голосования рисует общий
   лист «⋯» вверху экрана — под окном её не нажать. Экран обязан прятать окно, пока стол ждёт
   ответа игрока, и возвращать его, когда голосование кончилось отказом. Чистый node.

   Запуск:  node tests/домино-итог-раунда-при-голосовании.js
            node tests/домино-итог-раунда-при-голосовании.js --сломать
   Что делает:
     обычный запуск — настоящий js/домино-экран.js на поддельной странице (узлы — по id из
     настоящего домино.html), настоящий видДляИгрока из server/игры/домино.js, шесть случаев:
       (1) окно итогов открыто, пришло предложение — окно спрятано;
       (2) голосование кончилось отказом — окно вернулось в том же раунде;
       (3) игрок сам закрыл окно до предложения — оно не возвращается;
       (4) партия кончилась по согласию — окна раунда нет, показан конец по согласию;
       (5) предложения нет — окно итогов работает как раньше;
       (6) стол на двоих — поведение прежнее (окно не прячется).
     --сломать — на КОПИЯХ js/домино-экран.js во временной папке системы портится по одной
     строке на каждый случай; копия обязана покраснеть именно на своём случае.
   Код выхода: 0 — зелено; 1 — провал; строка для порчи не нашлась — тоже провал. */
const assert = require('node:assert/strict');
const path = require('node:path');
const os = require('node:os');
const fs = require('node:fs');
const vm = require('node:vm');
const { spawnSync } = require('node:child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const ЭКРАН = path.join(КОРЕНЬ, 'js', 'домино-экран.js');

function довод(имя) {
  const n = process.argv.indexOf(имя);
  return n > 0 ? path.resolve(process.argv[n + 1]) : null;
}
const ФАЙЛ_ЭКРАНА = довод('--экран') || ЭКРАН;
const ЛОМАТЬ = process.argv.includes('--сломать');

const Д = require(path.join(КОРЕНЬ, 'server', 'игры', 'домино.js'));
const П = require(path.join(КОРЕНЬ, 'js', 'домино-правила'));
const Б = require(path.join(КОРЕНЬ, 'js', 'домино-бот'));
const { сделатьДокумент, сделатьПамять, поддельныеЧасы } = require('./поддельный-браузер');
const РАЗМЕТКА = fs.readFileSync(path.join(КОРЕНЬ, 'домино.html'), 'utf8');

let проверок = 0;
let провалов = 0;
function проверка(имя, дело) {
  проверок++;
  try { дело(); console.log('  ок      ' + имя); }
  catch (e) { провалов++; console.log('  ПРОВАЛ  ' + имя + ' — ' + (e && e.message)); }
}

/* Экран на поддельной странице: узлы — по id из настоящего домино.html. */
function запуститьЭкран() {
  const документ = сделатьДокумент();
  const память = сделатьПамять(false);
  const идентификаторы = [...new Set([...РАЗМЕТКА.matchAll(/\sid="([^"]+)"/g)].map(с => с[1]).concat(['дом-рейтинг', 'дом-профиль', 'кнопка-лобби-назад']))];
  assert.ok(идентификаторы.length > 50, 'в домино.html нашлось мало узлов: ' + идентификаторы.length);
  for (const id of идентификаторы) {
    const узел = документ.createElement('div');
    узел.id = id;
    if (id.startsWith('экран-') || id === 'дом-настройки') узел.className = 'экран';
    узел.open = false;
    узел.showModal = () => { узел.open = true; };
    узел.close = () => { узел.open = false; };
    документ.body.appendChild(узел);
    if (id === 'дом-итог-середина') узел.appendChild(документ.createElement('details'));
  }
  const окно = {
    document: документ, localStorage: память, addEventListener() {}, matchMedia: () => ({ matches: false }),
    ДоминоПравила: П, ДоминоБот: Б,
    ДоминоКости: { кость: () => документ.createElement('div'), цепь() {} },
    ДоминоПамять: { восстановить() { return null; } },
    ДеберцСказать: () => ({ открыть() {}, принять() {} }),
    ЛистЕщё: { подключить: () => ({ освежитьКнопкуНастроек() {}, открыт: () => false, закрыть() {}, открыть() {} }) },
    ЭкранРейтинга: { открыть() {}, открытьСчёт() {} },
    Телеграм: { показатьСтрелку() {} },
    Сеть: { отправитьХод: async () => ({ принято: true }), покинутьПартию() {} }
  };
  const песочница = {
    window: окно, document: документ, localStorage: память, location: { href: '' }, console,
    setTimeout, clearTimeout, setInterval: () => 0, Date: поддельныеЧасы(1000000).Дата, matchMedia: окно.matchMedia
  };
  vm.createContext(песочница);
  vm.runInContext(fs.readFileSync(ФАЙЛ_ЭКРАНА, 'utf8'), песочница, { filename: 'домино-экран.js' });
  const узел = id => документ.getElementById(id);
  return {
    узел,
    показать: вид => окно.ИграПоСети.показатьВид(вид),
    окноИтогаОткрыто: () => узел('дом-результат').open === true,
    закрытьОкноСамому: () => узел('дом-посмотреть').onclick()   // кнопка «Посмотреть» в окне итога
  };
}

const ПРЕДЛОЖЕНИЕ_ЖДЁТ_МЕНЯ = { идёт: true, предложил: 1, имя: 'Боря', нужно: 2, за: 1, против: 0, голосуют: 3, мойГолос: null, яГолосую: true, секунд: 30, можноПредложить: false, почему: null };
const ПРЕДЛОЖЕНИЯ_НЕТ = { идёт: false, предложил: null, имя: null, нужно: 2, за: 0, против: 0, голосуют: 3, мойГолос: null, яГолосую: true, секунд: 0, можноПредложить: true, почему: null };

let номерВида = 0;
/* Вид стола, как его присылает сервер, но раунд уже кончился (фаза «итог»). */
function видИтога({ мест = 3, досрочно = ПРЕДЛОЖЕНИЯ_НЕТ, фаза = 'итог', прерван = false, раунд = null } = {}) {
  const п = Д.раздать(null, { игроки: ['и1', 'и2', 'и3', 'и4'].slice(0, мест) });
  const в = Д.видДляИгрока(п, 'и1', { код: 'ТЕСТ', версия: ++номерВида, номерСобытия: 1 });
  в.сыграноПартий = 0;
  в.домино.ход = 1;
  в.домино.фаза = фаза;
  if (раунд !== null) в.домино.раунд = раунд;
  if (прерван) { в.домино.прерван = true; в.домино.победители = []; }
  if (досрочно) в.досрочно = { ...досрочно };
  return в;
}

console.log('Окно итогов раунда и голосование');

проверка('(1) окно итогов открыто, пришло предложение — окно спрятано, плашке ничто не мешает', () => {
  const э = запуститьЭкран();
  э.показать(видИтога());
  assert.equal(э.окноИтогаОткрыто(), true, 'до предложения окно итогов не открылось — проверка не о том');
  э.показать(видИтога({ досрочно: ПРЕДЛОЖЕНИЕ_ЖДЁТ_МЕНЯ }));
  assert.equal(э.окноИтогаОткрыто(), false, 'окно итогов осталось поверх плашки голосования');
});

проверка('(1б) предложение пришло вместе с новым итогом раунда — окно не открывается', () => {
  const э = запуститьЭкран();
  э.показать(видИтога({ досрочно: ПРЕДЛОЖЕНИЕ_ЖДЁТ_МЕНЯ }));
  assert.equal(э.окноИтогаОткрыто(), false, 'окно открылось поверх плашки');
});

проверка('(2) голосование кончилось отказом — окно итогов вернулось в том же раунде', () => {
  const э = запуститьЭкран();
  э.показать(видИтога());
  э.показать(видИтога({ досрочно: ПРЕДЛОЖЕНИЕ_ЖДЁТ_МЕНЯ }));
  assert.equal(э.окноИтогаОткрыто(), false, 'окно не спряталось — проверка не о том');
  э.показать(видИтога({ досрочно: ПРЕДЛОЖЕНИЯ_НЕТ }));
  assert.equal(э.окноИтогаОткрыто(), true, 'окно итогов не вернулось');
  assert.match(э.узел('дом-итог-заголовок').textContent, /^Раунд №/, 'вернулось окно не раунда: ' + э.узел('дом-итог-заголовок').textContent);
});

проверка('(3) игрок сам закрыл окно до предложения — после отказа оно не возвращается', () => {
  const э = запуститьЭкран();
  э.показать(видИтога());
  э.закрытьОкноСамому();
  assert.equal(э.окноИтогаОткрыто(), false, 'окно не закрылось кнопкой «Посмотреть» — проверка не о том');
  э.показать(видИтога({ досрочно: ПРЕДЛОЖЕНИЕ_ЖДЁТ_МЕНЯ }));
  э.показать(видИтога({ досрочно: ПРЕДЛОЖЕНИЯ_НЕТ }));
  assert.equal(э.окноИтогаОткрыто(), false, 'окно, закрытое самим игроком, вернулось');
});

проверка('(4) партия кончилась по согласию — окна раунда нет, показан конец по согласию', () => {
  const э = запуститьЭкран();
  э.показать(видИтога());
  э.показать(видИтога({ досрочно: ПРЕДЛОЖЕНИЕ_ЖДЁТ_МЕНЯ }));
  // Сервер шлёт поле и после конца: голосования уже нет, а игрок числится голосующим.
  э.показать(видИтога({ досрочно: ПРЕДЛОЖЕНИЯ_НЕТ, фаза: 'конец', прерван: true }));
  assert.equal(э.окноИтогаОткрыто(), true, 'окно конца партии не открылось');
  assert.equal(э.узел('дом-итог-заголовок').textContent, 'Партия закончена по согласию');
  assert.doesNotMatch(э.узел('дом-итог-заголовок').textContent, /Раунд №/);
});

проверка('(5) предложения нет — окно итогов открывается и закрывается как раньше', () => {
  const э = запуститьЭкран();
  э.показать(видИтога({ досрочно: null }));
  assert.equal(э.окноИтогаОткрыто(), true, 'без поля «досрочно» окно не открылось');
  э.закрытьОкноСамому();
  э.показать(видИтога({ досрочно: null }));
  assert.equal(э.окноИтогаОткрыто(), false, 'закрытое окно открылось само');
  const э2 = запуститьЭкран();
  э2.показать(видИтога({ досрочно: ПРЕДЛОЖЕНИЯ_НЕТ }));
  assert.equal(э2.окноИтогаОткрыто(), true, 'с полем «идёт: false» окно не открылось');
  э2.показать(видИтога({ досрочно: ПРЕДЛОЖЕНИЯ_НЕТ, раунд: 2 }));
  assert.equal(э2.окноИтогаОткрыто(), true, 'новый итог следующего раунда не открылся');
});

проверка('(5б) игрок уже ответил на предложение — окно итогов не прячется', () => {
  const э = запуститьЭкран();
  э.показать(видИтога({ досрочно: { ...ПРЕДЛОЖЕНИЕ_ЖДЁТ_МЕНЯ, мойГолос: 'против' } }));
  assert.equal(э.окноИтогаОткрыто(), true, 'ответил, а окно спрятано');
});

проверка('(6) стол на двоих — поведение прежнее: окно итогов не прячется', () => {
  const э = запуститьЭкран();
  э.показать(видИтога({ мест: 2 }));
  э.показать(видИтога({ мест: 2, досрочно: ПРЕДЛОЖЕНИЕ_ЖДЁТ_МЕНЯ }));
  assert.equal(э.окноИтогаОткрыто(), true, 'вдвоём окно спряталось');
});

/* ---------- Ломающие запуски на копиях (--сломать) ---------- */
