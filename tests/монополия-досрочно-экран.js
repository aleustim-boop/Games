/** Партия на двоих, закончена сдачей; кто сдался — 'я' или 'соперник'. */
function конецСдачей(кто) {
  const п = партия(2);
  const я = п.игроки[0];   // смотрим глазами первого места
  const сдаётся = кто === 'я' ? я : п.игроки.find(к => к !== я);
  const r = Мон.сделатьХод(п, сдаётся, { действие: 'сдаться' });
  assert.equal(r.принято, true, 'сдача не принята: ' + r.причина);
  return п;
}
function видКонца(п, ключ) {
  return Мон.видДляИгрока(п, ключ, { код: 'ТЕСТ', версия: ++номерВида, сыграноПартий: 0 });
}

проверка('вид без признака и с фазой «finished»: прежний итог с победителем (соперник победил)', () => {
  const п = конецСдачей('я');
  const в = видКонца(п, п.игроки[0]);
  assert.equal(в.монополия.phase, 'finished');
  assert.equal(в.монополия.прервана, false, 'сервер назвал обычный конец прерванным');
  const э = запуститьЭкран();
  э.показать(в);
  assert.equal(э.узел('mono-modal').open, true);
  assert.equal(э.узел('mono-modal-title').textContent, 'Партия завершена');
  assert.match(э.узел('mono-modal-body').textContent, /Победитель: /);
  assert.doesNotMatch(текстОкна(э), /по согласию|В рейтинг партия не записывается/);
  assert.match(э.узел('mono-turn').textContent, /^Победитель: /);
  assert.deepEqual(э.подписи(э.узел('mono-actions')), ['Итоги партии']);
});

