/** Запустить настоящий экран; вернуть узлы, счётчики и вход «показать вид». */
function запуститьЭкран() {
  const документ = Браузер.сделатьДокумент();
  const создатьУзел = документ.createElement;
  // classList.replace и animate есть в браузере, в общей подделке их нет — экран ими пользуется
  документ.createElement = function (тег) {
    const у = создатьУзел(тег);
    у.classList.replace = function (было, стало) { у.classList.remove(было); у.classList.add(стало); };
    у.animate = function () {};
    return у;
  };
  const уже = new Set();
  for (const у of узлыРазметки) {
    if (уже.has(у.id)) continue;
    уже.add(у.id);
    const узел = документ.createElement(у.тег);
    узел.id = у.id; узел.className = у.класс;
    if (у.тег === 'dialog') {
      узел.open = false;
      узел.showModal = () => { узел.open = true; };
      узел.close = () => { узел.open = false; };
    }
    документ.body.appendChild(узел);
  }
  // Узлы, которые ставят общие скрипты страницы (не разметка): заводим пустыми по первому обращению.
  const настоящий = документ.getElementById;
  документ.getElementById = function (id) {
    let у = настоящий(id);
    if (!у) { у = документ.createElement('div'); у.id = id; документ.body.appendChild(у); }
    return у;
  };
  const вызовы = [];
  const память = Браузер.сделатьПамять(false);
  документ.__заготовки = {
    P: Правила, Д: Данные,
    Сеть: { отправитьХод: async (ход) => { вызовы.push(ход); return { принято: true }; } }
  };
  const заготовка =
    'var crypto = { getRandomValues: function (а) { а[0] = 12345; return а; } };' +
    'var matchMedia = window.matchMedia;' +
    // Наблюдатель за изменениями страницы: экран ставит его на плашку «Закончить партию?»
    // (игры/монополия/монополия-экран.js, следитьЗаГолосованием). Эта проверка плашку голосования не трогает
    // (она про итог и кнопки), поэтому пустышка честна: обратный вызов не нужен. Голосование — отдельная проверка.
    'var MutationObserver = function (дело) { this.дело = дело; };' +
    'MutationObserver.prototype.observe = function () {};' +
    'MutationObserver.prototype.disconnect = function () {};' +
    'window.МонополияПравила = document.__заготовки.P;' +
    'window.МонополияДанные = document.__заготовки.Д;' +
    'window.МонополияБот = {};' +
    'window.МонополияПоле = { colors: ["#1", "#2", "#3", "#4", "#5", "#6"], draw: function (доска, вид, нажатиеНаКлетку) { window.нажатиеНаКлетку = нажатиеНаКлетку; } };' +
    'window.Сеть = document.__заготовки.Сеть;' +
    'window.ЛистЕщё = { подключить: function () { return { открыть: function () {} }; } };\n';
  const мир = Браузер.поднять(заготовка + fs.readFileSync(довод('--экран') || ЭКРАН, 'utf8'), {
    память, документ, имяФайла: 'игры/монополия/монополия-экран.js'
  });
  const узел = id => документ.getElementById(id);
  return {
    мир, узел, вызовы, память,
    показать: вид => мир.окно.ИграПоСети.показатьВид(вид),
    /** Кнопки внутри узла, их подписи. */
    кнопки: корень => корень.querySelectorAll('button'),
    подписи: корень => корень.querySelectorAll('button').map(к => к.textContent),
    кнопка: (корень, подпись) => корень.querySelectorAll('button').find(к => к.textContent === подпись)
  };
}

/* ---------- Виды стола: настоящий видДляИгрока сервера ---------- */

let номерВида = 0;
/** Партия на троих; «моё» место — то, чей ход (чтобы у меня были кнопки хода). */
function партия(мест = 3) {
  const ключи = ['м1', 'м2', 'м3', 'м4', 'м5', 'м6'].slice(0, мест);
  const п = Мон.раздать(null, { игроки: ключи });
  п.игра = Правила.create(мест, 12345);   // зерно задано: бросок и порядок ходов не гуляют от запуска к запуску
  return п;
}
const мойКлюч = п => п.игроки[п.игра.turn];
function вид(п) {
  return Мон.видДляИгрока(п, мойКлюч(п), { код: 'ТЕСТ', версия: ++номерВида, сыграноПартий: 0 });
}
/** Партия, закрытая комнатой по согласию: как её оставляет закончитьПоСогласию (server/комнаты.js). */
function поСогласию(п) {
  п.завершена = true; п.законченаПоСогласию = true; п.результат = null; п.проигравшие = [];
  return п;
}
/** Партия, брошенная без итога и без согласия стола (например, соперник ушёл до первого хода). */
function отменённая(п) {
  п.завершена = true; п.результат = null; п.проигравшие = [];
  return п;
}
/** Бросок кубиков тем, чей ход: в виде появляются новые события. */
function бросить(п) {
  const r = Мон.сделатьХод(п, мойКлюч(п), { действие: 'монополия', move: { type: 'roll' } });
  assert.equal(r.принято, true, 'бросок не принят: ' + r.причина);
  return п;
}
