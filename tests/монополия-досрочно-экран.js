/** Экран, в котором идёт партия, и тот же стол после отмены без итога; прислали вид как есть (поле — по доводу). */
function послеОтмены(правитьВид) {
  const э = запуститьЭкран();
  const п = партия();
  э.показать(вид(п));
  отменённая(п);
  const в = вид(п);
  if (правитьВид) правитьВид(в);
  э.показать(в);
  return э;
}

