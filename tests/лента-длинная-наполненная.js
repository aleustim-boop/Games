'use strict';

/* =====================================================================
   ЛЕНТА «ЧТО БЫЛО» НА ДЛИННОЙ ИСТОРИИ.

   Ленту видели только на коротких партиях, а она растёт весь стол и
   ровно на длинной истории может уехать за край. Здесь она набивается
   по-настоящему: партия по сети, соперник — этот скрипт, игрок —
   настоящая страница в браузере, которая ходит сама («палец» из
   tests/автоигрок-в-браузере.js). Ничего не подделано.

   Что меряем сверх снимков:
     • доступны ли старые события — есть ли прокрутка и работает ли она;
     • видно ли ПОСЛЕДНЕЕ событие сразу, без прокрутки: лента нужна,
       чтобы понять, что только что произошло;
     • не растягивает ли страницу длинное имя в событии;
     • не тормозит ли лента, когда событий много (это единственное место,
       где список растёт без предела) — меряем на процессоре, замедленном
       вшестеро, как на слабом телефоне.

   Снимки кладутся в tests/скриншоты/ — оформитель смотрит туда.

   Запуск (страничный сервер и сервер комнат уже подняты):
       node tests/лента-длинная-наполненная.js 8080 8817
   ===================================================================== */

const http = require('http');
const path = require('path');
const { chromium, подготовитьПодделку } = require('./браузер-робот.js');

const ПОРТ_СТРАНИЦ = Number(process.argv[2]) || 8080;
const ПОРТ_КОМНАТ = Number(process.argv[3]) || 8817;
const ХОСТ = '127.0.0.1';
const ПАПКА_СНИМКОВ = 'tests/скриншоты/';
const ДЛИННОЕ_ИМЯ = 'Пал Палыч Загогулинский-Задунайский';

let провалов = 0;
function проверить(условие, слова) {
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}
const спать = (мс) => new Promise((ф) => setTimeout(ф, мс));

function запрос(путь, тело) {
  return new Promise(function (готово, беда) {
    const текст = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const о = http.request({
      host: ХОСТ, port: ПОРТ_КОМНАТ, method: 'POST', path: encodeURI(путь),
      headers: { 'Content-Type': 'application/json', 'Content-Length': текст.length }
    }, function (ответ) {
      let к = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (ч) { к += ч; });
      ответ.on('end', function () { try { готово(JSON.parse(к)); } catch (сбой) { готово({}); } });
    });
    о.on('error', беда);
    о.end(текст);
  });
}

/** Один ход соперника: перебираем то же, что перебирал бы человек пальцем. */
async function походитьСкриптом(код, пропуск, вид) {
  if (!вид || вид.завершена || !вид.яХожу) return false;
  if (вид.фаза === 'защита') {
    for (let пара = 0; пара < вид.стол.length; пара++) {
      if (вид.стол[пара].защита) continue;
      for (let карта = 0; карта < вид.мояРука.length; карта++) {
        const о = await запрос('/ход', { код, пропуск, действие: 'отбить', пара, карта });
        if (о.принято) return true;
      }
    }
    const беру = await запрос('/ход', { код, пропуск, действие: 'беру' });
    return беру.принято === true;
  }
  for (let карта = 0; карта < вид.мояРука.length; карта++) {
    const о = await запрос('/ход', { код, пропуск, действие: 'ходить', карта });
    if (о.принято) return true;
  }
  const бито = await запрос('/ход', { код, пропуск, действие: 'бито' });
  return бито.принято === true;
}

/** Что видно в ленте: события, прокрутка, последнее событие. */
async function осмотретьЛенту(страница) {
  return страница.evaluate(() => {
    const список = document.getElementById('лента-событий');
    if (!список) return null;
    /* События ищем по настоящей примете разметки. Если она поменяется,
       стенд скажет «событий 0» — а «ноль» мы всегда перепроверяем. */
    const события = [...список.children].filter((у) => у.getBoundingClientRect().height > 4);
    const к = список.getBoundingClientRect();
    const последнее = события.length ? события[события.length - 1].getBoundingClientRect() : null;
    const первое = события.length ? события[0].getBoundingClientRect() : null;
    return {
      событий: события.length,
      можноПрокрутить: Math.max(0, список.scrollHeight - список.clientHeight),
      прокрученоСейчас: Math.round(список.scrollTop),
      окноСписка: Math.round(к.top) + '…' + Math.round(к.bottom),
      последнееВидно: последнее ? (последнее.bottom <= к.bottom + 1 && последнее.top >= к.top - 1) : null,
      первоеВидно: первое ? (первое.top >= к.top - 1 && первое.bottom <= к.bottom + 1) : null,
      последнееСловами: события.length ? (события[события.length - 1].textContent || '').replace(/\s+/g, ' ').trim().slice(0, 60) : '',
      ширинаСтраницы: document.documentElement.scrollWidth,
      ширинаОкна: window.innerWidth
    };
  });
}

(async () => {
  console.log('Лента «Что было» на длинной истории. Страницы: ' + ПОРТ_СТРАНИЦ + ', комнаты: ' + ПОРТ_КОМНАТ);
  const браузер = await chromium.launch();

  for (const размер of [{ ш: 390, в: 844 }, { ш: 360, в: 640 }, { ш: 320, в: 568 }]) {
    console.log('\n=== ' + размер.ш + '×' + размер.в + ' ===');
    const окно = await браузер.newContext({ viewport: { width: размер.ш, height: размер.в }, hasTouch: true, deviceScaleFactor: 2 });
    const страница = await окно.newPage();
    const красные = [];
    страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
    страница.on('console', (м) => {
      if (м.type() !== 'error') return;
      const откуда = (м.location && м.location() && м.location().url) || '';
      if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
      красные.push('консоль: ' + м.text());
    });
    await подготовитьПодделку(страница, { версия: '8.0', полныйЭкран: 'дают' });
    await страница.goto('http://127.0.0.1:' + ПОРТ_СТРАНИЦ + '/?сервер=http://127.0.0.1:' + ПОРТ_КОМНАТ);
    await спать(600);

    /* Комнату заводит скрипт — с нарочно длинным именем: оно попадёт
       в события ленты, и там его и посмотрим. */
    const создание = await запрос('/создать', { имя: ДЛИННОЕ_ИМЯ, мест: 2 });
    if (!создание.код) { проверить(false, 'комнату завести не вышло'); await окно.close(); continue; }

    /* С 11 сентября вход по коду — «Есть код? Войти» прямо в лобби дурака
       (прежние «Играть с другом» → «Войти по коду» спрятаны за лобби). */
    await страница.click('#кнопка-игра-дурак'); await спать(250);
    await страница.click('#лобби-код'); await спать(400);
    await страница.fill('#поле-кода', создание.код);
    await страница.click('#кнопка-войти');
    await спать(1800);

    /* Стол на два места сервер считает «компанией»: партию начинает хозяин
       кнопкой «Начать», сама она не стартует. Без этого лента остаётся
       пустой, и стенд честно писал «событий 0». */
    await запрос('/ход', { код: создание.код, пропуск: создание.пропуск, действие: 'начать' });
    await спать(1200);
    const первый = (await запрос('/состояние', { код: создание.код, пропуск: создание.пропуск })).состояние || {};
    console.log('  после входа: этап=' + первый.этап + ', яХожу=' + первый.яХожу + ', соперникПришёл=' + первый.соперникПришёл + ', карт=' + ((первый.мояРука||[]).length));

    /* Игрок в браузере ходит сам — тем же «пальцем», что и в других стендах. */
    await страница.addScriptTag({ path: path.join(__dirname, 'автоигрок-в-браузере.js') });
    await страница.evaluate(() => window.Автоигрок.начать(0.7, false, 0));

    /* Соперник — этот скрипт. Играем, пока история не станет длинной. */
    /* Играем не «сколько-нибудь ходов», а пока история не станет длинной:
       лента показывает не каждый ход, а события («взял», «бито», «предлагает
       ещё») — на партию их выходит около восьми. Считаем их по номеру
       события, который сервер шлёт в состоянии. */
    let ходов = 0;
    let событий = 0;
    const срок = Date.now() + 150000;
    while (Date.now() < срок && событий < 30 && ходов < 600) {
      const вид = (await запрос('/состояние', { код: создание.код, пропуск: создание.пропуск })).состояние;
      if (!вид) break;
      событий = Math.max(событий, Number(вид.номерСобытия) || 0);
      if (вид.завершена) {
        await запрос('/ход', { код: создание.код, пропуск: создание.пропуск, действие: 'ещё' });
        await спать(600);
        continue;
      }
      if (вид.яХожу) { if (await походитьСкриптом(создание.код, создание.пропуск, вид)) ходов++; }
      else await спать(150);
    }
    await страница.evaluate(() => { try { window.Автоигрок.стоп(); } catch (о) {} });
    console.log('  ходов скрипта: ' + ходов + ', событий по счёту сервера: ' + событий);

    /* Открываем ленту так же, как человек: нажатием на строку подсказки. */
    await страница.evaluate(() => { if (window.открытьЛенту) window.открытьЛенту(); });
    await спать(700);

    const лента = await осмотретьЛенту(страница);
    if (!лента) { проверить(false, 'ленту на странице не нашли вовсе'); await окно.close(); continue; }
    console.log('  событий: ' + лента.событий + ', окно списка ' + лента.окноСписка +
      ', можно прокрутить на ' + лента.можноПрокрутить + 'px');
    console.log('  последнее: «' + лента.последнееСловами + '»');

    /* Оказалось, лента НЕ растёт без предела: она держит последние восемь
       событий и перенумеровывает их с единицы. Сервер за это время насчитал
       десятки. Поэтому требуем не «двадцать строк», а «лента наполнена
       и в ней ровно то, что она хранит». */
    console.log('  лента держит ' + лента.событий + ' событий, сервер за партию насчитал ' + событий);
    проверить(лента.событий >= 5, 'лента наполнена: событий ' + лента.событий);
    проверить(/только что/i.test(лента.последнееСловами) || лента.последнееВидно === true,
      'последнее событие помечено как свежее и видно сразу: «' + лента.последнееСловами + '»');
    проверить(лента.последнееВидно === true,
      'последнее событие видно сразу, без прокрутки (оно и нужно человеку)');
    проверить(лента.ширинаСтраницы <= лента.ширинаОкна + 1,
      'длинное имя в событии не растянуло страницу: ' + лента.ширинаСтраницы + ' при ' + лента.ширинаОкна);

    /* Старые события: если список длиннее окна, он обязан прокручиваться,
       и прокрутка обязана РАБОТАТЬ, а не просто числиться. */
    if (лента.можноПрокрутить > 0) {
      const доехали = await страница.evaluate(() => {
        const с = document.getElementById('лента-событий');
        с.scrollTop = 0;
        const вверху = с.scrollTop;
        s_прокрутить(с);
        function s_прокрутить(у) { у.scrollTop = у.scrollHeight; }
        return { вверху: вверху, внизу: Math.round(с.scrollTop) };
      });
      console.log('  прокрутка: вверх ' + доехали.вверху + ', вниз ' + доехали.внизу);
      проверить(доехали.внизу > доехали.вверху,
        'до старых событий можно доехать: прокрутка работает');
    } else {
      console.log('  (список короче окна — прокручивать нечего, старые события и так видны)');
    }

    /* Скорость: та же лента на слабом телефоне. Меряем открытие и кадры. */
    const связь = await страница.context().newCDPSession(страница);
    await связь.send('Emulation.setCPUThrottlingRate', { rate: 6 });
    const медленно = await страница.evaluate(() => new Promise((готово) => {
      const начало = performance.now();
      const с = document.getElementById('лента-событий');
      с.scrollTop = 0;
      const кадры = [];
      let прошлый = performance.now();
      let n = 0;
      function шаг(время) {
        кадры.push(время - прошлый);
        прошлый = время;
        с.scrollTop += 40;
        if (++n < 60) requestAnimationFrame(шаг);
        else {
          кадры.sort((а, б) => а - б);
          готово({
            середина: Math.round(кадры[Math.floor(кадры.length / 2)] * 10) / 10,
            худший: Math.round(кадры[кадры.length - 1]),
            всего: Math.round(performance.now() - начало)
          });
        }
      }
      requestAnimationFrame(шаг);
    }));
    await связь.send('Emulation.setCPUThrottlingRate', { rate: 1 });
    console.log('  на слабом телефоне: кадр обычно ' + медленно.середина + ' мс, худший ' +
      медленно.худший + ' мс, вся прокрутка ' + медленно.всего + ' мс');
    проверить(медленно.середина <= 40,
      'листание ленты не тормозит даже на слабом телефоне: кадр ' + медленно.середина + ' мс');

    проверить(красные.length === 0, 'консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));
    await страница.screenshot({ path: ПАПКА_СНИМКОВ + 'лента-длинная-' + размер.ш + '.png', fullPage: true });
    console.log('  снимок: ' + ПАПКА_СНИМКОВ + 'лента-длинная-' + размер.ш + '.png');

    await запрос('/выйти', { код: создание.код, пропуск: создание.пропуск });
    await окно.close();
  }

  await браузер.close();
  console.log('\nИтог: провалов ' + провалов);
  process.exit(провалов ? 1 : 0);
})().catch((о) => { console.error('Стенд упал: ' + (о && о.stack || о)); process.exit(2); });
