/* =====================================================================
   МОНОПОЛИЯ: ОТДЕЛЬНЫЙ ПРИЗНАК «ПАРТИЯ ЗАКОНЧЕНА ПО СОГЛАСИЮ».

   Только node: без браузера, playwright, сети и портов.
   Раньше в виде монополии стояла одна «прервана» — и для конца по согласию стола,
   и для отмены без итога, поэтому экран не мог честно написать «по согласию».
   Теперь сервер шлёт отдельное булево поле «поСогласию» (как домино), экран читает его.

   Что проверяем:
     С) server/игры/монополия.js (через require, без сети): поСогласию — false, пока партия идёт
        или прервана не по согласию (законченаПоСогласию не выставлена), и true после согласия;
        строго булево (не любое «правдивое» значение); ничего лишнего игроку не уходит;
        без партии (стол ждёт игроков) поле тоже есть и false.
     Э) js/монополия-экран.js в поддельном браузере (tests/поддельный-браузер.js):
        - признак true  → в заголовке и в окне итога «Партия закончена по согласию»;
        - признак false → «Партия закончена без победителя», слов «по согласию» нет;
        - поля нет (старый сервер) → так же, как false: ложного «по согласию» не бывает;
        - идёт обычная партия, а признак true (мусор) → «по согласию» не пишем (заголовок — обычный ход);
        - консоль чистая во всех случаях, текст непустой (ноль найденного — провал).

   Запуск:
       node tests/монополия-согласие.js                      — настоящие файлы, зелёное
       node tests/монополия-согласие.js --порчи <папка>      — то же, потом каждая порча на копии
                                                               в <папка> (вне проекта) обязана покраснеть
   Ломающие запуски по отдельности (обязаны покраснеть, выход 1) портят КОПИЮ в <папка>:
       --сломать-сервер-ложно <папка>   сервер: поСогласию = «партия завершена» (и отмена без итога станет «согласием»)
       --сломать-сервер-строго <папка>  сервер: любое «правдивое» законченаПоСогласию считается согласием
       --сломать-экран-всегда <папка>   экран: признак игнорируется, всегда «согласие»
       --сломать-экран-нет <папка>      экран: признак игнорируется, никогда «согласие»
       --сломать-экран-заголовок <папка> экран: заголовок над полем не читает признак
   Не нашли место порчи ровно один раз — выход 2 (ошибка запуска, не зелёное).
   Код выхода: 0 — зелено; 1 — провал; 2 — ошибка запуска.
   ===================================================================== */

const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const { spawnSync } = require('node:child_process');
const Браузер = require('./поддельный-браузер.js');

const КОРЕНЬ = path.join(__dirname, '..');
const СЕРВЕР = path.join(КОРЕНЬ, 'server', 'игры', 'монополия.js');
const ЭКРАН = path.join(КОРЕНЬ, 'js', 'монополия-экран.js');
const ПРАВИЛА = path.join(КОРЕНЬ, 'js', 'монополия-правила.js');
const ДАННЫЕ = path.join(КОРЕНЬ, 'js', 'монополия-данные.js');

const ПО_СОГЛАСИЮ = 'Партия закончена по согласию';
const БЕЗ_ПОБЕДИТЕЛЯ = 'Партия закончена без победителя';

/* ---------- порчи: что заменить в копии какого файла ---------- */
const ПОРЧИ = {
  '--сломать-сервер-ложно': {
    файл: 'сервер',
    было: 'поСогласию: p?.законченаПоСогласию === true,',
    стало: 'поСогласию: !!p?.завершена,',
  },
  '--сломать-сервер-строго': {
    файл: 'сервер',
    было: 'поСогласию: p?.законченаПоСогласию === true,',
    стало: 'поСогласию: Boolean(p?.законченаПоСогласию),',
  },
  '--сломать-экран-всегда': {
    файл: 'экран',
    было: 'network?.поСогласию === true ? СЛОВА_ПО_СОГЛАСИЮ : СЛОВА_БЕЗ_ПОБЕДИТЕЛЯ;',
    стало: 'СЛОВА_ПО_СОГЛАСИЮ;',
  },
  '--сломать-экран-нет': {
    файл: 'экран',
    было: 'network?.поСогласию === true ? СЛОВА_ПО_СОГЛАСИЮ : СЛОВА_БЕЗ_ПОБЕДИТЕЛЯ;',
    стало: 'СЛОВА_БЕЗ_ПОБЕДИТЕЛЯ;',
  },
  '--сломать-экран-заголовок': {
    файл: 'экран',
    было: '        : прерванаПоСогласию()\n          ? словаПрерванной()',
    стало: '        : прерванаПоСогласию()\n          ? СЛОВА_БЕЗ_ПОБЕДИТЕЛЯ',
  },
};

const АРГ = process.argv.slice(2);
const ВИД_ПОРЧИ = Object.keys(ПОРЧИ).find((к) => АРГ.includes(к)) || null;
const ПРОГОН_ПОРЧ = АРГ.includes('--порчи');

function ошибкаЗапуска(текст) {
  console.log('ошибка запуска: ' + текст);
  process.exit(2);
}

/* Папку для копий берём только из довода и только вне проекта. */
function папкаИзДовода(ключ) {
  const значение = АРГ[АРГ.indexOf(ключ) + 1];
  if (!значение || значение.startsWith('--')) ошибкаЗапуска('после ' + ключ + ' нужна папка вне проекта');
  const папка = path.resolve(значение);
  const отКорня = path.relative(КОРЕНЬ, папка);
  if (!отКорня.startsWith('..') && !path.isAbsolute(отКорня)) ошибкаЗапуска('папка внутри проекта: ' + папка);
  return папка;
}

/* Тексты проверяемых файлов: настоящие или копия с одной порчей. */
let текстСервера = fs.readFileSync(СЕРВЕР, 'utf8');
let текстЭкрана = fs.readFileSync(ЭКРАН, 'utf8');
if (ВИД_ПОРЧИ) {
  const папка = папкаИзДовода(ВИД_ПОРЧИ);
  const порча = ПОРЧИ[ВИД_ПОРЧИ];
  const исходный = (порча.файл === 'сервер' ? текстСервера : текстЭкрана).replace(/\r\n/g, '\n');
  const вхождений = исходный.split(порча.было).length - 1;
  if (вхождений !== 1) ошибкаЗапуска('место порчи устарело: нашлось ' + вхождений + ' раз, нужно 1');
  const испорченный = исходный.replace(порча.было, () => порча.стало);
  fs.mkdirSync(папка, { recursive: true });
  const куда = path.join(папка, порча.файл === 'сервер' ? 'монополия-сервер.js' : 'монополия-экран.js');
  fs.writeFileSync(куда, испорченный, 'utf8');
  if (порча.файл === 'сервер') текстСервера = испорченный;
  else текстЭкрана = испорченный;
  console.log('Ломающий запуск «' + ВИД_ПОРЧИ + '»: испорчена копия ' + куда + ', файлы проекта не тронуты\n');
}

let проверок = 0;
let провалов = 0;
function отметить(условие, текст) {
  проверок++;
  console.log((условие ? 'ок — ' : 'ПЛОХО — ') + текст);
  if (!условие) провалов++;
  return условие;
}

/* Серверный файл из текста: относительные require считаются от настоящей папки,
   поэтому копию можно проверять, не кладя её рядом с настоящими файлами. */
function загрузитьСервер(текст) {
  const м = new Module(СЕРВЕР, module);
  м.filename = СЕРВЕР;
  м.paths = Module._nodeModulePaths(path.dirname(СЕРВЕР));
  м._compile(текст, СЕРВЕР);
  return м.exports;
}

/* ---------- С. Сервер: вид игрока ---------- */
console.log('--- С: server/игры/монополия.js, поле «поСогласию» ---');
try {
  const М = загрузитьСервер(текстСервера);
  const новаяПартия = () => М.раздать(null, { игроки: ['а', 'б'] });
  const вид = (п) => М.видДляИгрока(п, 'а', { код: 'тест', этап: 'игра', версия: 1 });

  const идёт = вид(новаяПартия());
  отметить(идёт.поСогласию === false, 'С: партия идёт — поСогласию строго false (было ' + идёт.поСогласию + ')');
  отметить(!идёт.монополия.прервана, 'С: партия идёт — «прервана» не стоит');

  const отмена = новаяПартия();
  отмена.завершена = true;
  const видОтмены = вид(отмена);
  отметить(видОтмены.монополия.прервана === true, 'С: отмена без итога — «прервана» стоит (экран ждать хода не будет)');
  отметить(видОтмены.поСогласию === false, 'С: отмена без итога — поСогласию false, это не согласие (было ' + видОтмены.поСогласию + ')');

  const согласие = новаяПартия();
  согласие.завершена = true;
  согласие.законченаПоСогласию = true;
  const видСогласия = вид(согласие);
  отметить(видСогласия.поСогласию === true, 'С: закончена по согласию — поСогласию true (было ' + видСогласия.поСогласию + ')');
  отметить(видСогласия.монополия.прервана === true, 'С: закончена по согласию — «прервана» тоже стоит');

  const мусор = новаяПартия();
  мусор.законченаПоСогласию = 'да';
  отметить(вид(мусор).поСогласию === false, 'С: «правдивое», но не true — не согласие (поле строго булево)');

  const безПартии = М.видДляИгрока(null, 'а', { код: 'тест', этап: 'прихожая', версия: 1 });
  отметить(безПартии.поСогласию === false, 'С: стол без партии — поле есть и false (было ' + безПартии.поСогласию + ')');

  отметить(!('законченаПоСогласию' in видСогласия) && !('законченаПоСогласию' in видСогласия.монополия),
    'С: внутреннее поле «законченаПоСогласию» игроку не уходит');
  отметить(typeof видСогласия.поСогласию === 'boolean', 'С: поле булево, не строка и не число');
} catch (е) {
  отметить(false, 'С: сценарий упал целиком (' + (е && е.message) + ')');
}

/* ---------- Э. Экран в поддельном браузере ---------- */
console.log('\n--- Э: js/монополия-экран.js читает признак ---');
const Правила = require(ПРАВИЛА);
const Данные = require(ДАННЫЕ);

function запуститьЭкран() {
  const документ = Браузер.сделатьДокумент();
  const создатьУзел = документ.createElement;
  документ.createElement = function (тег) {
    const у = создатьУзел(тег);
    у.classList.replace = function (было, стало) { у.classList.remove(было); у.classList.add(стало); };
    return у;
  };
  const настоящий = документ.getElementById;
  const узлы = Object.create(null);
  документ.getElementById = function (id) {
    let у = настоящий(id);
    if (!у) {
      у = документ.createElement('div');
      у.id = id;
      у.close = function () { у.open = false; };
      у.showModal = function () { у.open = true; };
      документ.body.appendChild(у);
    }
    узлы[id] = у;
    return у;
  };
  документ.__заготовки = { P: Правила, Д: Данные };
  const заготовка =
    'var crypto = { getRandomValues: function (а) { а[0] = 12345; return а; } };' +
    'var matchMedia = function () { return { matches: true }; };' +
    'var MutationObserver = function () {};' +
    'MutationObserver.prototype.observe = function () {};' +
    'MutationObserver.prototype.disconnect = function () {};' +
    'window.МонополияПравила = document.__заготовки.P;' +
    'window.МонополияДанные = document.__заготовки.Д;' +
    'window.МонополияБот = {};' +
    'window.МонополияПоле = { colors: ["#111", "#222", "#333", "#444", "#555", "#666"], draw: function () {} };' +
    'window.ЛистЕщё = { подключить: function () { return { открыть: function () {} }; } };\n';
  const мир = Браузер.поднять(заготовка + текстЭкрана, {
    память: Браузер.сделатьПамять(false), документ, имяФайла: 'js/монополия-экран.js',
  });
  return { мир, узлы, документ };
}

/* Показать экрану вид стола по сети. прервана — как её ставит сервер; доп — поля общего вида стола. */
function показать(прервана, доп) {
  const э = запуститьЭкран();
  const игра = Правила.create(2, 7);
  const вид = Правила.view(игра, 0);
  if (прервана) вид.прервана = true;
  э.мир.окно.ИграПоСети.показатьВид(Object.assign({ монополия: вид, код: 'тест', версия: 1, сыграноПартий: 0 }, доп));
  return {
    заголовок: э.узлы['mono-turn'] ? э.узлы['mono-turn'].textContent : '',
    всё: э.документ.body.textContent,
    консоль: э.мир.ошибкиКонсоли,
  };
}

function проверитьСлучай(название, прервана, доп, ждём) {
  try {
    const р = показать(прервана, доп);
    отметить(р.заголовок.length > 0, 'Э: ' + название + ' — заголовок найден и не пуст (ноль найденного — провал)');
    if (ждём !== null) {
      отметить(р.заголовок === ждём, 'Э: ' + название + ' — заголовок «' + ждём + '» (получили «' + р.заголовок + '»)');
    }
    if (прервана) {
      отметить(р.всё.includes(ждём), 'Э: ' + название + ' — окно итога называется «' + ждём + '»');
      const согласиеНаЭкране = р.всё.includes('по согласию');
      отметить(согласиеНаЭкране === (ждём === ПО_СОГЛАСИЮ),
        'Э: ' + название + ' — слова «по согласию» на экране ' + (ждём === ПО_СОГЛАСИЮ ? 'есть' : 'не появились'));
    } else {
      отметить(!р.всё.includes('по согласию'), 'Э: ' + название + ' — слов «по согласию» на экране нет');
    }
    отметить(р.консоль.length === 0, 'Э: ' + название + ' — консоль чистая (' + JSON.stringify(р.консоль) + ')');
  } catch (е) {
    отметить(false, 'Э: ' + название + ' — сценарий упал (' + (е && е.message) + ')');
  }
}

проверитьСлучай('сервер прислал поСогласию: true', true, { поСогласию: true }, ПО_СОГЛАСИЮ);
проверитьСлучай('сервер прислал поСогласию: false (отмена без итога)', true, { поСогласию: false }, БЕЗ_ПОБЕДИТЕЛЯ);
проверитьСлучай('старый сервер, поля нет', true, {}, БЕЗ_ПОБЕДИТЕЛЯ);
проверитьСлучай('идёт обычная партия, признак true по ошибке', false, { поСогласию: true }, null);

отметить(/network\?\.поСогласию === true/.test(текстЭкрана),
  'Э: исходник экрана читает признак строго («network?.поСогласию === true»)');

console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);
const зелено = провалов === 0 && проверок > 0;

/* ---------- Прогон порч: каждая обязана покраснеть ---------- */
if (ПРОГОН_ПОРЧ && !ВИД_ПОРЧИ) {
  const папка = папкаИзДовода('--порчи');
  let непокраснели = 0;
  for (const имя of Object.keys(ПОРЧИ)) {
    const р = spawnSync(process.execPath, [__filename, имя, папка], { encoding: 'utf8' });
    const покраснела = р.status === 1;
    console.log((покраснела ? 'ок — порча покраснела: ' : 'ПЛОХО — порча НЕ покраснела (выход ' + р.status + '): ') + имя);
    if (!покраснела) непокраснели++;
  }
  console.log('Порч: ' + Object.keys(ПОРЧИ).length + ', покраснели: ' + (Object.keys(ПОРЧИ).length - непокраснели));
  process.exit(зелено && непокраснели === 0 ? 0 : 1);
}
process.exit(зелено ? 0 : 1);
