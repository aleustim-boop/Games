/* =====================================================================
   «Захват», А7: звук и вибрация (ТЗ, раздел 10). Проверка в node,
   без страницы: файл js/захват-звук.js запускается в песочнице vm
   с поддельным звуковым движком, поддельной памятью и поддельным Телеграм.

   Проверяем:
     1) каждый звук из списка ТЗ есть в файле, вызывается и создаёт узлы
        (генератор + громкость, соединены, запущены и остановлены);
     2) длительность звуков, у которых ТЗ называет миллисекунды;
     3) вибрация: нужный отклик по таблице ТЗ, у звуков без вибрации — ни одного;
     4) до первого звука движок не создан;
     5) выключено — ноль узлов у КАЖДОЙ функции файла, в том числе той,
        которой нет в списке ТЗ; выбор переживает «перезагрузку»;
     6) список в файле и список ТЗ совпадают (лишний звук — провал).

   Запуск:  node tests/захват-звук.js
   Довод:   --файл <путь>   — взять другой файл вместо js/захват-звук.js
   Порча:   --сломать       — на КОПИЯХ во временной папке портит файл двумя
                              способами и требует провала в каждом.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const vm = require('vm');
const { spawnSync } = require('child_process');

const ПАПКА_ПРОЕКТА = path.join(__dirname, '..');
const ФАЙЛ_ПО_УМОЛЧАНИЮ = path.join(ПАПКА_ПРОЕКТА, 'js', 'захват-звук.js');

/* Список ТЗ, раздел 10: звук, ожидаемая вибрация (вид отклика из
   js/telegram.js или null), длительность в секундах, если ТЗ её называет. */
const СПИСОК_ТЗ = [
  { имя: 'поставить',  вибро: 'лёгкий',   сек: 0.04 },
  { имя: 'приказ',     вибро: 'карта',    сек: 0.12 },
  { имя: 'отказ',      вибро: 'проигрыш', сек: 0.06 },
  { имя: 'готово',     вибро: null },
  { имя: 'тик',        вибро: null },
  { имя: 'раскрытие',  вибро: null,       сек: 0.6 },
  { имя: 'удар',       вибро: null,       сек: 0.15 },
  { имя: 'захват',     вибро: 'победа',   сек: 0.3 },
  { имя: 'потеря',     вибро: 'взятка',   сек: 0.25 },
  { имя: 'столица',    вибро: null,       сек: 0.5 },
  { имя: 'победа',     вибро: 'победа' },
  { имя: 'поражение',  вибро: 'нельзя' }
];
const СЛУЖЕБНЫЕ = ['включён', 'переключить'];

let провалов = 0;
let проверок = 0;
function проверить(условие, слова) {
  проверок++;
  console.log((условие ? '  ок   — ' : '  ПЛОХО— ') + слова);
  if (!условие) провалов++;
}

/* Поддельный мир: движок, память, Телеграм. Считает всё, что создали. */
function собратьМир(файл, память) {
  const мир = { движков: 0, генераторов: [], громкостей: 0, отклики: [] };
  function Движок() {
    мир.движков++;
    this.state = 'running';
    this.currentTime = 0;
    this.destination = {};
  }
  Движок.prototype.resume = function () { return Promise.resolve(); };
  Движок.prototype.createOscillator = function () {
    const о = { соединён: false, начало: null, конец: null, frequency: {
      setValueAtTime() {}, exponentialRampToValueAtTime() {} },
      connect() { о.соединён = true; },
      start(т) { о.начало = т; }, stop(т) { о.конец = т; } };
    мир.генераторов.push(о);
    return о;
  };
  Движок.prototype.createGain = function () {
    мир.громкостей++;
    return { gain: { setValueAtTime() {}, exponentialRampToValueAtTime() {} }, connect() {} };
  };
  const окно = {
    AudioContext: Движок,
    localStorage: {
      getItem: (к) => (к in память ? память[к] : null),
      setItem: (к, з) => { память[к] = String(з); }
    },
    Телеграм: { отклик: (вид) => { мир.отклики.push(вид); return true; } }
  };
  окно.window = окно;
  const песочница = vm.createContext(окно);
  vm.runInContext(fs.readFileSync(файл, 'utf8'), песочница, { filename: файл });
  мир.звук = окно.ЗахватЗвук;
  return мир;
}

function сброс(мир) {
  мир.генераторов.length = 0;
  мир.громкостей = 0;
  мир.отклики.length = 0;
}

function прогнать(файл) {
  const память = {};
  let мир;
  try {
    мир = собратьМир(файл, память);
  } catch (ошибка) {
    проверить(false, 'файл запускается без ошибок (' + ошибка.message + ')');
    return;
  }
  const звук = мир.звук;
  проверить(!!звук && typeof звук === 'object', 'файл отдаёт window.ЗахватЗвук');
  if (!звук) return;

  console.log('\n=== 1. Тишина до первого звука ===');
  проверить(мир.движков === 0, 'до первого звука движок не создан');

  console.log('\n=== 2. Каждый звук из списка ТЗ ===');
  проверить(СПИСОК_ТЗ.length === 12, 'в списке ТЗ раздела 10 двенадцать звуков (в проверке ' + СПИСОК_ТЗ.length + ')');
  for (const з of СПИСОК_ТЗ) {
    const функция = звук[з.имя];
    if (typeof функция !== 'function') {
      проверить(false, 'звук «' + з.имя + '» есть в файле');
      continue;
    }
    сброс(мир);
    функция();
    const г = мир.генераторов;
    проверить(г.length >= 1 && мир.громкостей >= 1, '«' + з.имя + '»: созданы узлы (генераторов ' + г.length + ', громкостей ' + мир.громкостей + ')');
    проверить(г.length >= 1 && г.every((о) => о.соединён && о.начало !== null && о.конец !== null),
      '«' + з.имя + '»: каждый генератор соединён, запущен и остановлен');
    if (з.сек) {
      const длина = г.length ? Math.max(...г.map((о) => о.конец)) - Math.min(...г.map((о) => о.начало)) : 0;
      проверить(Math.abs(длина - з.сек) <= 0.04, '«' + з.имя + '»: длится около ' + з.сек * 1000 + ' мс (вышло ' + Math.round(длина * 1000) + ')');
    }
    const ждали = з.вибро ? [з.вибро] : [];
    проверить(JSON.stringify(мир.отклики) === JSON.stringify(ждали),
      '«' + з.имя + '»: вибрация ' + (з.вибро ? '«' + з.вибро + '»' : 'нет') + ' (вышло ' + JSON.stringify(мир.отклики) + ')');
  }

  console.log('\n=== 3. Список в файле и список ТЗ совпадают ===');
  const вФайле = Object.keys(звук).filter((к) => typeof звук[к] === 'function' && !СЛУЖЕБНЫЕ.includes(к)).sort();
  const вТЗ = СПИСОК_ТЗ.map((з) => з.имя).sort();
  проверить(JSON.stringify(вФайле) === JSON.stringify(вТЗ),
    'звуки файла = звуки ТЗ (файл: ' + вФайле.join(', ') + ')');
  проверить(typeof звук.включён === 'function' && typeof звук.переключить === 'function', 'есть включён() и переключить()');

  console.log('\n=== 4. Выключатель ===');
  проверить(звук.включён() === true, 'по умолчанию звук включён');
  звук.переключить();
  проверить(звук.включён() === false, 'после переключения звук выключен');
  проверить(память['zahvat-sound'] === 'выключен', 'выбор записан в память под ключом zahvat-sound');
  for (const имя of вФайле) {
    сброс(мир);
    звук[имя]();
    проверить(мир.генераторов.length === 0 && мир.громкостей === 0,
      'выключено, «' + имя + '»: ноль узлов (генераторов ' + мир.генераторов.length + ', громкостей ' + мир.громкостей + ')');
  }
  /* «Перезагрузка»: тот же файл, та же память, новая песочница. */
  const мир2 = собратьМир(файл, память);
  проверить(мир2.звук.включён() === false, 'после перезагрузки звук остался выключенным');
  for (const имя of вФайле) {
    сброс(мир2);
    мир2.звук[имя]();
    if (мир2.генераторов.length || мир2.громкостей) {
      проверить(false, 'после перезагрузки выключено, «' + имя + '»: ноль узлов');
    }
  }
  проверить(мир2.движков === 0, 'после перезагрузки при выключенном звуке движок не создаётся');
  мир2.звук.переключить();
  проверить(мир2.звук.включён() === true && мир2.генераторов.length >= 1, 'включили снова — сразу слышно ответ');
}

/* Порча: два способа на копиях. Каждый обязан дать хотя бы один провал,
   и сама порча обязана найти, что портить. */
function сломать() {
  const исходник = fs.readFileSync(ФАЙЛ_ПО_УМОЛЧАНИЮ, 'utf8');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-звук-'));
  const порчи = [
    { имя: 'звук «удар» идёт в обход выключателя',
      испортить: (т) => т.replace('сигнал(2400, 0.04', 'сыграть(2400, 0.04') },
    { имя: 'звук «тик» удалён из списка',
      испортить: (т) => т.replace('    тик: звукТика,\n', '') }
  ];
  let подвело = 0;
  for (const порча of порчи) {
    const текст = порча.испортить(исходник);
    if (текст === исходник) {
      console.log('  ПЛОХО— порча «' + порча.имя + '» ничего не нашла в файле — проверка не может краснеть');
      подвело++;
      continue;
    }
    const копия = path.join(папка, 'копия.js');
    fs.writeFileSync(копия, текст, 'utf8');
    const итог = spawnSync(process.execPath, [__filename, '--файл', копия], { encoding: 'utf8' });
    const строка = (итог.stdout.match(/Итого проверок: \d+, провалов: \d+/) || ['(итога нет)'])[0];
    const покраснела = итог.status === 1 && /провалов: [1-9]/.test(строка);
    console.log((покраснела ? '  ок   — ' : '  ПЛОХО— ') + порча.имя + ': ' + строка + ', код ' + итог.status);
    if (!покраснела) подвело++;
  }
  fs.rmSync(папка, { recursive: true, force: true });
  console.log('\nПорч не замеченных проверкой: ' + подвело);
  process.exit(подвело ? 1 : 0);
}

const аргументы = process.argv.slice(2);
if (аргументы.includes('--сломать')) {
  сломать();
} else {
  const номер = аргументы.indexOf('--файл');
  const файл = номер >= 0 ? path.resolve(аргументы[номер + 1]) : ФАЙЛ_ПО_УМОЛЧАНИЮ;
  прогнать(файл);
  console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
}
