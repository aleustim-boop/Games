/** В СТРАНИЦЕ: показать стол как после ответа сервера. */
function показатьСтол(в) {
  if (!window.ИграПоСети || typeof window.ИграПоСети.показатьВид !== 'function') return 'нет window.ИграПоСети.показатьВид';
  window.ИграПоСети.показатьВид(в);
  return '';
}

/** В СТРАНИЦЕ: все замеры за один раз. */
function замерить() {
  const W = document.documentElement.clientWidth, H = window.innerHeight;
  const прям = function (р) { return { x: р.left, y: р.top, r: р.right, b: р.bottom, w: р.width, h: р.height }; };
  const видно = function (у) {
    if (!у) return false;
    const с = getComputedStyle(у), р = у.getBoundingClientRect();
    return с.display !== 'none' && с.visibility !== 'hidden' && Number(с.opacity) > 0.05 && р.width > 0 && р.height > 0 &&
      !у.closest('.скрыт') && !у.closest('[hidden]');
  };
  const итог = { W: W, H: H, вбок: document.documentElement.scrollWidth - W };
  итог.карточки = Array.from(document.querySelectorAll('#соперники .соперник')).map(function (к) {
    const рк = к.getBoundingClientRect();
    const м = к.querySelector('.соперник__метка');
    let метка = null;
    if (м) {
      const рм = м.getBoundingClientRect(), с = getComputedStyle(м);
      const диап = document.createRange(); диап.selectNodeContents(м);
      const рт = диап.getBoundingClientRect();
      const ц = document.elementFromPoint((рм.left + рм.right) / 2, (рм.top + рм.bottom) / 2);
      метка = Object.assign({ текст: м.textContent.trim(), виден: видно(м), размерШрифта: parseFloat(с.fontSize),
        // Обрезано: содержимое шире окошка или стоит многоточие, а слова не уместились.
        обрезан: м.scrollWidth > м.clientWidth + 1 || м.scrollHeight > м.clientHeight + 2,
        словаШире: рт.width > рм.width + 1,
        сама: Boolean(ц) && (м === ц || м.contains(ц)),
        внутри: рм.left >= рк.left - 0.5 && рм.right <= рк.right + 0.5 && рм.top >= рк.top - 0.5 && рм.bottom <= рк.bottom + 0.5 }, прям(рм));
    }
    const аватар = getComputedStyle(к, '::before'), сон = getComputedStyle(к, '::after');
    // Рамка значка «z z»: у псевдоэлемента нет getBoundingClientRect, поэтому считаем из его стиля —
    // позиция absolute от верхнего левого угла внутренней части карточки, ширина текста — по canvas.
    let значок = null;
    if (/z/.test(сон.content) && сон.position === 'absolute') {
      const холст = document.createElement('canvas').getContext('2d');
      холст.font = сон.fontStyle + ' ' + сон.fontWeight + ' ' + сон.fontSize + ' ' + сон.fontFamily;
      const буквСпейс = parseFloat(сон.letterSpacing) || 0;
      const текстШ = холст.measureText('z z').width + буквСпейс * 3;
      const ск = getComputedStyle(к);
      const лево = рк.left + parseFloat(ск.borderLeftWidth) + parseFloat(сон.left);
      const верх = рк.top + parseFloat(ск.borderTopWidth) + parseFloat(сон.top);
      значок = { размерШрифта: parseFloat(сон.fontSize), x: лево, y: верх, r: лево + текстШ, b: верх + parseFloat(сон.fontSize) * 1.2, w: текстШ };
    }
    return Object.assign({
      значок: значок,
      аватарПрозрачность: Number(аватар.opacity), аватарФильтр: аватар.filter,
      значокСна: сон.content, ходит: к.classList.contains('соперник--ходит'), бот: к.classList.contains('соперник--бот'),
      имя: (к.querySelector('.соперник__имя') || { textContent: '' }).textContent.trim(),
      классы: к.className, спит: к.classList.contains('соперник--спит'), ушёл: к.classList.contains('соперник--ушёл'),
      виден: видно(к), метка: метка, текст: к.textContent.replace(/\s+/g, ' ').trim()
    }, прям(рк));
  });
  return итог;
}

/* ---------- Разбор ---------- */

const пересекаются = function (а, б) { return а.x < б.r - 0.5 && б.x < а.r - 0.5 && а.y < б.b - 0.5 && б.y < а.b - 0.5; };
const коорд = function (р) { return Math.round(р.x) + ',' + Math.round(р.y) + '–' + Math.round(р.r) + ',' + Math.round(р.b); };

function разобрать(размер, р) {
  const п = размер.w + 'px · ';
  const м = р.м;
  проверить(р.ошПоказа === '', п + 'стол показан через ИграПоСети.показатьВид' + (р.ошПоказа ? ' (' + р.ошПоказа + ')' : ''));
  if (!проверить(м.карточки.length === 3, п + 'за столом на 4 места видно 3 плашки соседей (найдено: ' + м.карточки.length + ')')) return;
  проверить(м.вбок <= 0, п + '[карточка] горизонтальной прокрутки нет (лишних точек: ' + м.вбок + ')');

  const спящие = м.карточки.filter(function (к) { return к.спит; });
  const ушедшие = м.карточки.filter(function (к) { return к.ушёл; });
  const обычные = м.карточки.filter(function (к) { return !к.спит && !к.ушёл; });
  проверить(спящие.length === 1 && ушедшие.length === 1 && обычные.length === 1,
    п + 'один спящий, один ушедший, один обычный (спящих ' + спящие.length + ', ушедших ' + ушедшие.length + ', обычных ' + обычные.length + '; классы: ' +
    м.карточки.map(function (к) { return '«' + к.классы + '»'; }).join(', ') + ')');

  if (спящие.length === 1) {
    const с = спящие[0], мт = с.метка;
    if (проверить(Boolean(мт), п + '[метка-видна] у спящего «' + с.имя + '» есть узел метки')) {
      проверить(мт.текст === СЛОВА_СНА, п + '[метка-видна] слова метки — «' + СЛОВА_СНА + '» (на экране: «' + мт.текст + '»)');
      проверить(мт.виден, п + '[метка-видна] метка на виду (не display:none, не прозрачная)');
      проверить(мт.размерШрифта >= 11, п + '[метка-видна] шрифт метки читаемый, не меньше 11 точек (вышло: ' + мт.размерШрифта + ')');
      проверить(мт.сама, п + '[метка-видна] в середине метки — она сама, её ничто не закрывает');
      проверить(!мт.обрезан && !мт.словаШире, п + '[метка-цела] слова не обрезаны ни краем, ни многоточием (обрезана: ' + мт.обрезан + ', слова шире окошка: ' + мт.словаШире + ', ширина окошка ' + Math.round(мт.w) + ')');
      проверить(мт.внутри, п + '[метка-в-карточке] метка целиком внутри карточки (метка ' + коорд(мт) + ', карточка ' + коорд(с) + ')');
    }
    проверить(с.виден && с.x >= -0.5 && с.r <= м.W + 0.5 && с.y >= -0.5 && с.b <= м.H + 0.5, п + '[карточка] карточка спящего целиком в экране (' + коорд(с) + ', экран ' + м.W + '×' + м.H + ')');
    const другие = м.карточки.filter(function (к) { return к !== с; });
    const самая = Math.max.apply(null, другие.map(function (к) { return к.w; }));
    проверить(с.w <= самая + 0.5, п + '[карточка] карточка спящего не шире соседних (спящий ' + Math.round(с.w) + ', самая широкая из других ' + Math.round(самая) + ')');
    проверить(другие.every(function (к) { return !пересекаются(с, к); }), п + '[карточка] карточка спящего не наезжает на соседние');
    проверить(с.текст.indexOf(СЛОВА_СНА) !== -1, п + '[метка-видна] слова «' + СЛОВА_СНА + '» есть в тексте карточки спящего');
    // Узнаваемость: аватар заметно притушен и обесцвечен, рядом значок сна.
    проверить(с.аватарПрозрачность <= 0.3 && /grayscale/.test(с.аватарФильтр),
      п + '[спящий-притушен] аватар спящего притушен и обесцвечен (прозрачность ' + с.аватарПрозрачность + ', фильтр «' + с.аватарФильтр + '»)');
    проверить(/z/.test(с.значокСна), п + '[спящий-притушен] у аватара спящего значок сна (содержимое: ' + с.значокСна + ')');
    // Значок сна: крупный, не на метке, не за краем карточки.
    const зн = с.значок;
    if (проверить(Boolean(зн), п + '[значок-размер] у значка сна есть рамка (absolute, содержимое «z z»)')) {
      проверить(зн.размерШрифта >= 14, п + '[значок-размер] шрифт значка «z z» не меньше 14 точек (вышло: ' + зн.размерШрифта + ')');
      проверить(зн.x >= с.x - 0.5 && зн.r <= с.r + 0.5 && зн.y >= с.y - 0.5 && зн.b <= с.b + 0.5,
        п + '[значок-место] значок целиком внутри карточки (значок ' + коорд(зн) + ', карточка ' + коорд(с) + ')');
      if (мт) проверить(!пересекаются(зн, мт), п + '[значок-место] значок не пересекает метку (значок ' + коорд(зн) + ', метка ' + коорд(мт) + ')');
    }
    // Карточка спящего по размеру такая же, как у обычного соседа (на этом столе они в одной раскладке).
    if (обычные.length === 1) {
      проверить(Math.abs(с.w - обычные[0].w) <= 1 && Math.abs(с.h - обычные[0].h) <= 1,
        п + '[размер-карточки] карточка спящего ' + Math.round(с.w) + '×' + Math.round(с.h) + ' = карточка обычного ' + Math.round(обычные[0].w) + '×' + Math.round(обычные[0].h));
    }
  }

  if (ушедшие.length === 1) {
    const у = ушедшие[0];
    проверить(у.текст.indexOf(СЛОВА_СНА) === -1, п + '[ушёл] у ушедшего «' + у.имя + '» слов «' + СЛОВА_СНА + '» нет (текст карточки: «' + у.текст + '»)');
    проверить(Boolean(у.метка) && у.метка.текст === 'ушёл', п + '[ушёл] у ушедшего своя метка «ушёл» (вышло: «' + (у.метка ? у.метка.текст : 'нет метки') + '»)');
  }
  if (обычные.length === 1) {
    const о = обычные[0];
    проверить(о.текст.indexOf(СЛОВА_СНА) === -1 && !(о.метка && о.метка.текст === СЛОВА_СНА), п + '[обычный] у обычного «' + о.имя + '» слов «' + СЛОВА_СНА + '» нет (текст карточки: «' + о.текст + '»)');
    проверить(о.имя === 'Святослав' && !/(^|\s)бот(\s|$)/.test(о.текст.replace(о.имя, '')) && !о.бот && !о.спит && !о.ушёл,
      п + '[обычный] Святослав — обычный человек без пометки «бот» (текст карточки: «' + о.текст + '», класс бота: ' + о.бот + ')');
    проверить(!о.ходит && !спящие.some(function (к) { return к.ходит; }), п + '[сцена] рамки «чей ход» у соседей нет — ходит не спящий');
  }
  // Сцена одна на обеих ширинах: тот же порядок соседей.
  const порядок = м.карточки.map(function (к) { return к.имя; }).join(' > ');
  проверить(порядок === 'Александра > Константин > Святослав', п + '[сцена] порядок соседей слева направо: Александра, Константин, Святослав (вышло: ' + порядок + ')');
  if (порядокПервой === null) порядокПервой = порядок;
  else проверить(порядок === порядокПервой, п + '[сцена] порядок соседей тот же, что на первой ширине (было «' + порядокПервой + '», стало «' + порядок + '»)');
  проверить(р.ошибки.length === 0, п + '[консоль] ошибок в консоли нет' + (р.ошибки.length ? ': ' + р.ошибки.join(' | ') : ''));
}

