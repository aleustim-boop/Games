#!/usr/bin/env node
'use strict';

/* =====================================================================
   РЕЙТИНГ — «СЛУШАТЕЛЬ ПАРТИЙ» (план штаб/план-позвать-друга.md, Э2).

   Зачем. Учёт приглашений должен узнавать, что партия учтена и кто в ней
   сыграл, но рейтинг про приглашения не знает: он зовёт подписчиков,
   подписанных через слушатьПартии(функция). Слушатель получает
   (игра, номераЛюдейВСчёте, {источник: 'стол' | 'билет' | 'неизвестно'}).

   ЧТО ПРОВЕРЯЕМ (память рейтинга — во временной папке):
     а) обычная партия — слушатель зван один раз, с верной игрой и номерами;
     б) повтор того же ключа партии — слушатель НЕ зван второй раз;
     в) «сам с собой» — ноль вызовов;
     г) боты и места вне счёта в номерах отсутствуют;
     д) слушатель бросил ошибку — очки всё равно начислены, второй слушатель
        всё равно позван;
     е) источник: переданный 'стол'/'билет' доходит, не переданный или
        незнакомый — 'неизвестно'.

   УМЕЕТ ЛИ КРАСНЕТЬ. --сломать [папка] берёт КОПИЮ server/рейтинг.js
   (во временной папке, либо в названной вне проекта), вырезает из неё вызов
   слушателей и гоняет те же случаи: обязана провалиться.

   Запуск:
       node tests/рейтинг-слушатель.js
       node tests/рейтинг-слушатель.js --сломать [папка вне проекта]
   Выход 0 — провалов нет, 1 — провал.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const позицияЛомки = process.argv.indexOf('--сломать');
const ЛОМАТЬ = позицияЛомки !== -1;
const ПАПКА_ЛОМКИ = ЛОМАТЬ ? process.argv[позицияЛомки + 1] : undefined;

let всегоПроверок = 0;
let провалов = 0;
function проверить(что, условие, подробности) {
  всегоПроверок++;
  if (!условие) {
    провалов++;
    console.log('  ПРОВАЛ ' + что + (подробности ? ': ' + подробности : ''));
  } else {
    console.log('  ок     ' + что);
  }
}

function человек(номер, исход, дополнительно) {
  return Object.assign({
    номер: номер, имя: 'Игрок' + номер, этоБот: false,
    победил: исход === 'победа', ничья: исход === 'ничья'
  }, дополнительно || {});
}

// Свои временные папки (в %TEMP%) убираем по окончании. Папку, названную
// снаружи через --сломать, не трогаем — она чужая.
const папкиНаУдаление = [];
function удалитьВременное() {
  for (const п of папкиНаУдаление) {
    try { fs.rmSync(п, { recursive: true, force: true }); } catch (_) { /* не критично */ }
  }
}

/** Путь к рейтингу: настоящий, либо испорченная копия (без вызова слушателей). */
function путьКРейтингу() {
  if (!ЛОМАТЬ) return path.join(КОРЕНЬ, 'server', 'рейтинг.js');
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: в копии server/рейтинг.js вырезан вызов слушателей ***\n');
  const врем = ПАПКА_ЛОМКИ && !ПАПКА_ЛОМКИ.startsWith('--')
    ? ПАПКА_ЛОМКИ
    : fs.mkdtempSync(path.join(os.tmpdir(), 'рейтинг-слушатель-сломать-'));
  fs.mkdirSync(врем, { recursive: true });
  // server/данные — личные данные игроков, в копию не берём.
  const ПАПКА_ДАННЫХ = path.join(КОРЕНЬ, 'server', 'данные');
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(врем, 'server'), {
    recursive: true,
    filter: function (откуда) { return откуда !== ПАПКА_ДАННЫХ && !откуда.startsWith(ПАПКА_ДАННЫХ + path.sep); }
  });
  папкиНаУдаление.push(врем);
  // server/игры/умолчания.js берёт список игр из общего реестра.
  require('./пути-проекта.js').создатьПапкиКода(врем);
  fs.copyFileSync(path.join(КОРЕНЬ, 'общее', 'js', 'игры-реестр.js'), path.join(врем, 'общее', 'js', 'игры-реестр.js'));
  const копия = path.join(врем, 'server', 'рейтинг.js');
  const исходник = fs.readFileSync(копия, 'utf8');
  const было = '  сообщитьСлушателямПартий(игра, застольем, источник);';
  if (исходник.indexOf(было) === -1) {
    console.log('порча не нашла место: вызов слушателей в server/рейтинг.js изменился, поправьте проверку');
    удалитьВременное();
    process.exit(2);
  }
  fs.writeFileSync(копия, исходник.replace(было, '  /* ИСПОРЧЕНО: вызов слушателей вырезан */'), 'utf8');
  return копия;
}

// server/папка-данных.js сначала смотрит ДАННЫЕ_ИГРЫ, потом GAMES_DATA — задаём оба.
const ПАПКА_ПАМЯТИ = fs.mkdtempSync(path.join(os.tmpdir(), 'рейтинг-слушатель-'));
папкиНаУдаление.push(ПАПКА_ПАМЯТИ);
process.env.ДАННЫЕ_ИГРЫ = ПАПКА_ПАМЯТИ;
process.env.GAMES_DATA = ПАПКА_ПАМЯТИ;
const рейтинг = require(путьКРейтингу());

const вызовы = [];
рейтинг.слушатьПартии(function (игра, номера, сведения) {
  вызовы.push({ игра: игра, номера: номера, источник: сведения && сведения.источник });
});

/* а) обычная партия */
рейтинг.учестьПартию('дурак', [человек(101, 'победа'), человек(102, 'поражение')], 'слушатель-а', 'стол');
проверить('(а) обычная партия — один вызов', вызовы.length === 1, 'вызовов: ' + вызовы.length);
проверить('(а) игра и номера верные',
  вызовы.length > 0 && вызовы[0].игра === 'дурак' && JSON.stringify(вызовы[0].номера) === '[101,102]',
  JSON.stringify(вызовы[0]));
проверить('(е) источник «стол» дошёл', вызовы.length > 0 && вызовы[0].источник === 'стол');

/* б) повтор того же ключа */
рейтинг.учестьПартию('дурак', [человек(101, 'победа'), человек(102, 'поражение')], 'слушатель-а', 'стол');
проверить('(б) повтор того же ключа — слушатель не зван снова', вызовы.length === 1, 'вызовов: ' + вызовы.length);

/* в) сам с собой */
вызовы.length = 0;
рейтинг.учестьПартию('дурак', [человек(201, 'победа'), человек(201, 'поражение')], 'слушатель-в', 'стол');
проверить('(в) «сам с собой» — ноль вызовов', вызовы.length === 0, 'вызовов: ' + вызовы.length);

/* г) боты и места вне счёта */
вызовы.length = 0;
рейтинг.учестьПартию('дурак', [
  человек(301, 'победа'),
  человек(302, 'поражение'),
  человек(303, 'поражение', { внеСчёта: true }),
  { номер: null, имя: 'Бот', этоБот: true, победил: false, ничья: false }
], 'слушатель-г', 'билет');
проверить('(г) один вызов', вызовы.length === 1, 'вызовов: ' + вызовы.length);
проверить('(г) в номерах только люди в счёте (301, 302)',
  вызовы.length > 0 && JSON.stringify(вызовы[0].номера) === '[301,302]',
  JSON.stringify(вызовы[0]));
проверить('(е) источник «билет» дошёл', вызовы.length > 0 && вызовы[0].источник === 'билет');

/* человек против бота — человек в списке один, бот нет */
вызовы.length = 0;
рейтинг.учестьПартию('дурак', [
  человек(311, 'победа'),
  { номер: 9000000000000001, имя: 'Бот', этоБот: true, победил: false, ничья: false }
]);
проверить('(г) человек против бота (без ключа) — только человек, источник «неизвестно»',
  вызовы.length === 1 && JSON.stringify(вызовы[0].номера) === '[311]' && вызовы[0].источник === 'неизвестно',
  JSON.stringify(вызовы));

/* е) источник выводится из ключа, если 4-й довод не передан (как зовут комнаты и билеты) */
вызовы.length = 0;
рейтинг.учестьПартию('дурак', [человек(331, 'победа'), человек(332, 'поражение')], 'обычный-ключ-стола');
проверить('(е) три довода, обычный ключ → «стол»', вызовы.length === 1 && вызовы[0].источник === 'стол',
  JSON.stringify(вызовы));
вызовы.length = 0;
рейтинг.учестьПартию('дурак', [человек(341, 'победа'), человек(342, 'поражение')], 'билет:abc123');
проверить('(е) три довода, ключ «билет:…» → «билет»', вызовы.length === 1 && вызовы[0].источник === 'билет',
  JSON.stringify(вызовы));

/* е) незнакомый источник */
вызовы.length = 0;
рейтинг.учестьПартию('дурак', [человек(321, 'победа'), человек(322, 'поражение')], 'слушатель-е', 'выдумка');
проверить('(е) незнакомый источник → «неизвестно»', вызовы.length === 1 && вызовы[0].источник === 'неизвестно',
  JSON.stringify(вызовы));

/* д) слушатель бросил ошибку */
let второйПозван = 0;
рейтинг.слушатьПартии(function () { throw new Error('слушатель сломался нарочно'); });
рейтинг.слушатьПартии(function () { второйПозван++; });
const прежнийЛог = console.log;
console.log = function () {};   // ошибка слушателя печатается в лог — в выводе проверки она лишняя
let ответ;
let упало = false;
try {
  ответ = рейтинг.учестьПартию('дурак', [человек(401, 'победа'), человек(402, 'поражение')], 'слушатель-д', 'стол');
} catch (ошибка) {
  упало = true;
}
console.log = прежнийЛог;
проверить('(д) ошибка слушателя не роняет рейтинг', !упало);
проверить('(д) очки начислены', !упало && ответ && ответ[401] > 0, JSON.stringify(ответ));
проверить('(д) слушатель после упавшего всё равно позван', второйПозван === 1, 'позван: ' + второйПозван);

console.log('');
console.log('Итого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
удалитьВременное();
process.exit(провалов > 0 ? 1 : 0);
