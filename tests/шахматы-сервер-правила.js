/* ---------- 11. Сторож полей вида ---------- */
console.log('\nСторож полей вида');
{
  const ВЕРХ = ['игра', 'код', 'этап', 'версия', 'номерСобытия', 'событие', 'видСобытия', 'имяСобытия',
    'сыграноПартий', 'открытыйСтол', 'яХочуЕщё', 'соперникХочетЕщё', 'соперникПришёл', 'соперникНаСвязи',
    'соперникУшёл', 'мест', 'мойНомер', 'знакиВниманияЕсть', 'броскиЕсть', 'предложениеНичьей',
    'можноПредложитьНичью', 'креслоСоперника', 'fen', 'доска', 'чейХод', 'мойЦвет', 'яХожу', 'шах',
    'завершена', 'последнийХод', 'итог', 'застолом', 'яХозяин', 'можноНачать'];
  const ВНУТРИ = {
    последнийХод: ['откуда', 'куда', 'запись', 'чей', 'мой'],
    итог: ['победитель', 'ничья', 'причина', 'яВыиграл'],
    предложениеНичьей: ['моё', 'ждётМеня']
  };
  /* Поля одного места в списке «застолом» — свой белый список: внутреннего
     имени места («ключ») тут быть не должно, экран узнаёт своё место по
     признаку «этоЯ». */
  const ПОЛЯ_МЕСТА = ['номер', 'имя', 'этоЯ', 'этоБот', 'хозяин', 'наСвязи', 'ушёл', 'хочетЕщё', 'цвет'];

  /* Стол на двоих: комната поля «места» вовсе не шлёт — так выглядит
     обычная партия вдвоём, не компания с прихожей. */
  const добавкаНаДвоих = {
    код: 'АБВГ', этап: 'игра', версия: 3, номерСобытия: 7, событие: 'Вы: ход',
    событиеСырое: { что: 'ход', кто: Б, имя: 'Аня' },
    знакСырой: { номер: 1, кто: Б }, пропуск: 'секрет', мест: 2, мойНомер: 1
  };
  /* Прихожая (стол-компания): список мест непустой — у комнаты это и есть
     признак «компания» (server/комнаты.js: сделатьСтолНаДвоихКомпанией,
     посадитьБота, безХозяина — все они кладут «места» только для неё). */
  const добавкаКомпании = Object.assign({}, добавкаНаДвоих, {
    места: [
      { ключ: Б, имя: 'Аня', номер: 1, хозяин: true, этоБот: false, наСвязи: true, ушёл: false, хочетЕщё: false },
      { ключ: Ч, имя: 'Боря', номер: 2, хозяин: false, этоБот: true, наСвязи: true, ушёл: false, хочетЕщё: false }
    ],
    яХозяин: true,
    можноНачать: true
  });

  function осмотреть(вид, где) {
    const лишние = Object.keys(вид).filter(function (к) { return ВЕРХ.indexOf(к) === -1; });
    Object.keys(ВНУТРИ).forEach(function (к) {
      if (вид[к] && typeof вид[к] === 'object') {
        Object.keys(вид[к]).forEach(function (в) { if (ВНУТРИ[к].indexOf(в) === -1) лишние.push(к + '.' + в); });
      }
    });
    if (Array.isArray(вид.застолом)) {
      вид.застолом.forEach(function (место, i) {
        Object.keys(место).forEach(function (в) {
          if (ПОЛЯ_МЕСТА.indexOf(в) === -1) лишние.push('застолом[' + i + '].' + в);
        });
      });
    }
    проверить(где + ': в виде только поля из белого списка', лишние.length === 0, лишние.join(', '));
    const текст = JSON.stringify(вид);
    проверить(где + ': внутренних имён мест и пропуска в виде нет',
      текст.indexOf('"' + Б + '"') === -1 && текст.indexOf('"' + Ч + '"') === -1 && текст.indexOf('секрет') === -1);
  }
  /* Стол на двоих: списка мест нет ВООБЩЕ — ни пустого, ни какого-либо. */
  function осмотретьНаДвоих(вид, где) {
    осмотреть(вид, где);
    проверить(где + ': стол на двоих — списка мест и признаков компании нет',
      !('застолом' in вид) && !('яХозяин' in вид) && !('можноНачать' in вид));
  }
  /* Прихожая: список мест ЕСТЬ, с признаками хозяина и «можно начать». */
  function осмотретьКомпанию(вид, где) {
    осмотреть(вид, где);
    проверить(где + ': прихожая — список мест есть, длиной со стол',
      Array.isArray(вид.застолом) && вид.застолом.length === 2, JSON.stringify(вид.застолом));
    проверить(где + ': прихожая — признаки хозяина и «можно начать» дошли',
      вид.яХозяин === true && вид.можноНачать === true);
  }

  const п = новаяПартия();
  осмотретьНаДвоих(Шахматы.видДляИгрока(null, Б, добавкаНаДвоих), 'до раздачи, стол на двоих');
  осмотретьНаДвоих(Шахматы.видДляИгрока(п, Б, добавкаНаДвоих), 'начало партии, стол на двоих');
  const компания = Шахматы.видДляИгрока(п, Б, добавкаКомпании);
  осмотретьКомпанию(компания, 'начало партии, прихожая');
  проверить('в прихожей у моего места виден мой цвет, у чужого — не мой',
    Array.isArray(компания.застолом) && компания.застолом.length === 2 &&
    компания.застолом[0].этоЯ === true && компания.застолом[0].цвет === 'белые' &&
    компания.застолом[1].этоЯ === false && компания.застолом[1].этоБот === true,
    JSON.stringify(компания.застолом));
  ход(п, Б, 'e2', 'e4');
  Шахматы.сделатьХод(п, Ч, { действие: 'ничья' });
  осмотретьНаДвоих(Шахматы.видДляИгрока(п, Б, добавкаНаДвоих), 'после хода и предложения ничьей');
  Шахматы.сделатьХод(п, Б, { действие: 'сдаться' });
  const конец = Шахматы.видДляИгрока(п, Ч, добавкаНаДвоих);
  осмотретьНаДвоих(конец, 'после конца партии');
  проверить('в конце есть итог и последний ход (сторож видел вложенные поля)',
    Boolean(конец.итог) && Boolean(конец.последнийХод));
  проверить('вид события взят из закрытого набора', конец.видСобытия === 'ход');
}

