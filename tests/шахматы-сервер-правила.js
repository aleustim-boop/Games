const Б = 'первый';   // внутренние имена мест, как у комнаты
const Ч = 'второй';

/** Партия, где белые — Б, чёрные — Ч. */
function новаяПартия() {
  return Шахматы.раздать(Б, { игроки: [Б, Ч] });
}

/** Партия из FEN — для особых позиций. */
function партияИзFEN(fen) {
  const партия = новаяПартия();
  партия.позиция = Правила.партияИзFEN(fen);
  return партия;
}

function ход(партия, кто, откуда, куда, превращение) {
  const намерение = { действие: 'ход', откуда: откуда, куда: куда };
  if (превращение !== undefined) намерение.превращение = превращение;
  return Шахматы.сделатьХод(партия, кто, намерение);
}

/** Сыграть ходы по очереди, начиная с белых. Вернуть последний ответ. */
function сыграть(партия, ходы) {
  let ответ = null;
  ходы.forEach(function (пара, i) {
    ответ = ход(партия, i % 2 === 0 ? Б : Ч, пара[0], пара[1]);
    if (!ответ.принято) throw new Error('Ход ' + пара.join('-') + ' не принят: ' + ответ.причина);
  });
  return ответ;
}

function fen(партия, кто) { return Шахматы.видДляИгрока(партия, кто || Б, {}).fen; }

