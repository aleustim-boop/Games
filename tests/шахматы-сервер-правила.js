const fs = require('fs');
const path = require('path');
const Module = require('module');

const ПАПКА_ИГР = path.join(__dirname, '..', 'server', 'игры');
const НАСТОЯЩИЙ = path.join(ПАПКА_ИГР, 'шахматы.js');

/* Какой файл игры проверяем: настоящий или испорченную копию. */
function загрузитьИгру() {
  const i = process.argv.indexOf('--сломать');
  if (i === -1) return { игра: require(НАСТОЯЩИЙ), откуда: НАСТОЯЩИЙ };
  const копия = process.argv[i + 1];
  if (!копия || !fs.existsSync(копия)) {
    console.error('Для --сломать нужен путь к существующей копии файла игры');
    process.exit(2);
  }
  if (path.resolve(копия) === path.resolve(НАСТОЯЩИЙ)) {
    console.error('--сломать портит только КОПИЮ, а не настоящий файл');
    process.exit(2);
  }
  /* Собираем модуль из текста копии, но «живёт» он в папке server/игры —
     тогда его относительные require находят настоящие правила и бота. */
  const имя = path.join(ПАПКА_ИГР, '__копия-для-порчи__.js');
  const модуль = new Module(имя, null);
  модуль.filename = имя;
  модуль.paths = Module._nodeModulePaths(ПАПКА_ИГР);
  модуль._compile(fs.readFileSync(копия, 'utf8'), имя);
  return { игра: модуль.exports, откуда: копия };
}

