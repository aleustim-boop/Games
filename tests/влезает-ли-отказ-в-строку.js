/* =====================================================================
   ВЛЕЗАЕТ ЛИ СТРОКА ПОДСКАЗКИ В ОТВЕДЁННОЕ ЕЙ МЕСТО.

   ЭТО НЕ АВТОПРОГОН ДЛЯ NODE. Файл вставляется в консоль браузера, когда
   игра уже открыта. Здесь меряется живой экран настоящей ширины — 390,
   320 или 280 точек, — а не поддельный.

   ЗАЧЕМ. Внизу экрана у игры одна строка на всё. Коробка под неё жёсткая
   (в оформлении ей отведено 60 точек высоты и «лишнее прячем»), поэтому
   слишком длинный текст не переносится ниже, а СРЕЗАЕТСЯ — и человек
   читает обрубок. Так была найдена поломка: отказ «7♥ не подкинуть: на
   столе только 6, 7, 8, 9, 10, В или Д» рядом с напоминанием «что делать»
   не влезал никуда.

   ЧЕМ ЭТОТ ЗАМЕР ОТЛИЧАЕТСЯ ОТ «самая-длинная-подсказка.js». Тот считает
   длину текста в знаках в поддельном браузере — он отвечает на вопрос
   «какая строка бывает самой длинной». Этот смотрит на НАСТОЯЩИЙ экран
   и отвечает на другой вопрос — «а влезла ли она». Знаки тут ни при чём:
   одна и та же длина в знаках влезает на 390 точках и срезается на 280.

   КАК СЧИТАЕТ. Ни одна строка сюда не переписана. К узлу, куда игра
   пишет подсказку, приставлен наблюдатель: каждый раз, когда текст
   меняется, замер тут же меряет узел по-настоящему — сколько высоты
   тексту нужно и сколько ему отведено. Строка, которой нужно больше, —
   и есть срезанная.

   ЧТО ЗАПУСКАТЬ (звать по одному):

     влезает.записывать()
         Приставить наблюдателя. Дальше можно играть руками или пустить
         «Автоигрок.начать()» — всё, что покажет строка, будет записано.

     влезает.тыкатьВовсю(60)
         Шестьдесят кругов: ткнуть подряд в каждую карту руки (дважды),
         в каждую карту на столе, в колоду, в козырь и мимо карт, а потом
         сделать законный ход, чтобы стол двигался. Это и есть тот самый
         нетерпеливый человек, который трогает всё подряд.

     влезает.столИзНаходки()
         Отдельно — тот самый стол из находки: семь разных достоинств
         на столе и карта в руке, которой не подкинуть. Стол собирается
         из настоящей раздачи, а карты в него кладутся правилами игры,
         а не руками (см. «собратьСтолИзНаходки»).

     влезает.отчёт()
         Что видел экран: сколько строк записано, самые длинные, и —
         главное — список срезанных.

     влезает.стоп()
   ===================================================================== */

(function () {
  'use strict';

  const пауза = (мс) => new Promise((r) => setTimeout(r, мс));
  const узелТекста = () => document.getElementById('подсказка-текст');
  const узелКоробки = () => document.getElementById('подсказка');

  /* Всё, что экран показал: текст → как он померился. Ключ по тексту,
     чтобы одна и та же фраза не забивала отчёт сотней повторов. */
  const виденное = new Map();
  let наблюдатель = null;
  let ширинаЭкрана = 0;

  /**
   * Померить строку по-настоящему. «Срезано» — это когда тексту нужно
   * больше места, чем ему отведено: коробка прячет лишнее, и человек
   * читает обрубок.
   */
  function померить() {
    const т = узелТекста();
    const к = узелКоробки();
    if (!т || !к) return null;
    const текст = т.textContent || '';
    return {
      текст: текст,
      знаков: текст.length,
      ширинаЭкрана: window.innerWidth,
      нужноВысоты: т.scrollHeight,
      отведеноВысоты: т.clientHeight,
      нужноШирины: т.scrollWidth,
      отведеноШирины: т.clientWidth,
      высотаКоробки: к.clientHeight,
      /* Плюс единица — на дробные точки: браузер округляет высоту строки,
         и ровно влезающий текст иногда отличается на десятую долю точки. */
      срезано: (т.scrollHeight > т.clientHeight + 1) ||
               (т.scrollWidth > т.clientWidth + 1)
    };
  }

  function записать() {
    const м = померить();
    if (!м || !м.текст) return;
    const ключ = м.ширинаЭкрана + '|' + м.текст;
    if (!виденное.has(ключ)) виденное.set(ключ, м);
  }

  function записывать() {
    if (наблюдатель) return 'уже записываю';
    const т = узелТекста();
    if (!т) return 'узла подсказки нет — игра открыта?';
    ширинаЭкрана = window.innerWidth;
    наблюдатель = new MutationObserver(записать);
    наблюдатель.observe(т, { childList: true, characterData: true, subtree: true });
    записать();
    return 'записываю строки на ширине ' + ширинаЭкрана;
  }

  function стоп() {
    if (наблюдатель) { наблюдатель.disconnect(); наблюдатель = null; }
    return 'запись остановлена, строк записано: ' + виденное.size;
  }

  function забыть() { виденное.clear(); return 'записи стёрты'; }

  /* ------------------------------------------------------------------
     Тыкать во всё подряд — как делает живой человек, который не понял,
     почему игра его не слушается.
     ------------------------------------------------------------------ */

  /* Именно так, без «window.»: партия объявлена в игре через let, а такие
     на window не попадают вовсе. Первый заход этого замера с «window.партия»
     тихо решил, что партии нет никогда, и накрутил ноль кругов. */
  const партияИдёт = () => typeof партия !== 'undefined' && Boolean(партия) && !партия.завершена;

  /** Один законный ход за человека, чтобы стол не стоял. */
  function сходитьЗаконно() {
    if (!партияИдёт() || !сейчасМойХод()) return false;
    рукаГлухаДо = 0;
    const текущая = фаза(партия);
    if (текущая === 'защита') {
      for (let п = 0; п < партия.стол.length; п++) {
        if (партия.стол[п].защита) continue;
        for (let к = 0; к < партия.руки.человек.length; к++) {
          if (бьёт(партия.руки.человек[к], партия.стол[п].атака, партия.козырь)) {
            отбитьсяКартой(п, к);
            return true;
          }
        }
      }
      нажатьБеру();
      return true;
    }
    for (let к = 0; к < партия.руки.человек.length; к++) {
      if (можноПоложить(партия, партия.руки.человек[к])) { сходитьКартой(к); return true; }
    }
    if (мнеМожноЗакончитьПодход(текущая)) { нажатьБито(); return true; }
    return false;
  }

  /** Ткнуть во всё, что есть на экране, и записать каждый ответ. */
  async function ткнутьВоВсё() {
    if (!партияИдёт()) return;
    const рука = партия.руки.человек ? партия.руки.человек.length : 0;
    for (let к = 0; к < рука; к++) {
      // Дважды: на повтор игра отвечает другими словами — их тоже меряем.
      рукаГлухаДо = 0; тапПоКартеЧеловека(к); await пауза(35); записать();
      рукаГлухаДо = 0; тапПоКартеЧеловека(к); await пауза(35); записать();
    }
    for (let п = 0; п < партия.стол.length; п++) {
      рукаГлухаДо = 0; тапПоПаре(п); await пауза(35); записать();
    }
    рукаГлухаДо = 0; тапПоКолоде(); await пауза(35); записать();
    рукаГлухаДо = 0; тапПоКозырю(); await пауза(35); записать();
    рукаГлухаДо = 0;
    тапМимоКарты({ target: document.getElementById('карты-человека') });
    await пауза(35); записать();
  }

  async function тыкатьВовсю(кругов) {
    const надо = Number(кругов) || 40;
    if (!наблюдатель) записывать();
    const крайний = Date.now() + 20000 + надо * 3000;
    let сделано = 0;
    while (сделано < надо && Date.now() < крайний) {
      if (!партияИдёт()) { начатьПартию(); await пауза(600); continue; }
      await ткнутьВоВсё();
      сделано++;
      /* Ждём, пока отказ отсидит своё: после него в строку возвращается
         рассказ вместе с напоминанием — самая длинная пара, ради которой
         всё и затевалось. Без ожидания замер её просто не увидит. */
      await пауза(2600);
      записать();
      if (сейчасМойХод()) сходитьЗаконно();
      await пауза(400);
    }
    return { кругов: сделано, строкЗаписано: виденное.size };
  }

  /* ------------------------------------------------------------------
     Тот самый стол из находки: семь разных достоинств.

     Стол собирается не руками: берём настоящую раздачу и кладём в неё
     карты теми же правилами игры («можноПоложить», «бьёт»), какими это
     делает сама игра. Руками задаётся одно — какие карты у кого в руке,
     иначе нужного стола можно ждать сотню партий.
     ------------------------------------------------------------------ */

  /** Собрать карту по имени: «7♥» → { имя: '7', масть: '♥' }. */
  function карта(имя, масть) { return { имя: имя, масть: масть }; }

  /**
   * Стол из находки: четыре отбитых пары — семь разных достоинств
   * (стол полон парами, значит слово у того, кто ходил: он подкидывает).
   * Возвращает, что вышло, и слова отказа на карту, которой не подкинуть.
   */
  async function столИзНаходки() {
    if (!наблюдатель) записывать();
    начатьПартию();
    await пауза(500);
    // Останавливаем назначенный ход бота: иначе он сходит по своему
    // расписанию и разберёт собранный стол прямо посреди замера.
    if (typeof таймер !== 'undefined' && таймер !== null) { clearTimeout(таймер); таймер = null; }

    /* Козырь — трефы, чтобы ни одна карта стола козырем не оказалась:
       козырные пары путали бы картину. */
    партия.козырь = '♣';
    партия.стол = [
      { атака: карта('6', '♠'), защита: карта('7', '♠') },
      { атака: карта('8', '♦'), защита: карта('9', '♦') },
      { атака: карта('10', '♥'), защита: карта('В', '♥') },
      { атака: карта('Д', '♠'), защита: карта('6', '♦') }
    ];
    // Отбивается бот, и карт у него хватает — иначе игра откажет по другой
    // причине («больше не подкинуть»), и мы померили бы не ту строку.
    партия.руки.бот = [карта('К', '♠'), карта('Т', '♠'), карта('2', '♣'),
                       карта('3', '♣'), карта('4', '♣')];
    партия.руки.человек = [карта('7', '♥'), карта('2', '♦'), карта('5', '♠'),
                           карта('9', '♣'), карта('4', '♥'), карта('К', '♦')];
    партия.атакует = 'человек';
    партия.берёт = false;
    партия.пасы = [];
    перерисовать();
    await пауза(120);

    const достоинства = достоинстваНаСтоле(партия);
    записать();
    const дофазы = фаза(партия);
    const слово = ктоХодит(партия);

    // Тычем в карту, достоинства которой на столе нет: подкинуть нельзя.
    const плохая = партия.руки.человек.findIndex(
      (к) => достоинства.indexOf(к.имя) === -1);
    рукаГлухаДо = 0;
    тапПоКартеЧеловека(плохая >= 0 ? плохая : 1);
    await пауза(60);
    const свежий = померить();
    записать();

    // И через 2,6 с — то, что встанет в строку после отказа.
    await пауза(2600);
    const после = померить();
    записать();

    return {
      достоинствНаСтоле: достоинства.length,
      какие: достоинства.join(' '),
      фаза: дофазы,
      словоУ: слово,
      тыкали: плохая >= 0 ? названиеКарты(партия.руки.человек[плохая]) : '?',
      покаОтказСвежий: свежий,
      когдаОтказОтсидел: после
    };
  }

  /**
   * Померить строки, которые в игре с ботами не встречаются, а в игре
   * по сети встречаются: там в подсказку подставляется ИМЯ игрока
   * (сервер пропускает до шестнадцати знаков).
   *
   * Тексты сюда НЕ выдумываются: их выдаёт замер
   * «tests/самая-длинная-подсказка.js», который читает их у настоящей
   * игры и настоящего сервера. Здесь мы только кладём готовую строку
   * в тот самый узел экрана и смотрим, влезла ли она.
   *
   * Так проверяется то, до чего живой рукой добираться пришлось бы
   * часами: игрок с длинным именем должен выйти из партии и вернуться.
   */
  function померитьЧужиеСтроки(строки) {
    const т = узелТекста();
    if (!т) return 'узла подсказки нет';
    const было = т.textContent;
    const итог = (строки || []).map(function (с) {
      т.textContent = с;
      const м = померить();
      return { знаков: м.знаков, срезано: м.срезано,
               нужно: м.нужноВысоты, отведено: м.отведеноВысоты, текст: с };
    });
    т.textContent = было;
    return { ширинаЭкрана: window.innerWidth, строки: итог,
             срезанных: итог.filter((м) => м.срезано).length };
  }

  /* ------------------------------------------------------------------ */

  function отчёт() {
    const все = [...виденное.values()];
    const срезанные = все.filter((м) => м.срезано);
    const поДлине = все.slice().sort((а, б) => б.знаков - а.знаков);
    const итог = {
      ширинаЭкрана: window.innerWidth,
      строкЗаписано: все.length,
      срезанныхСтрок: срезанные.length,
      самаяДлинная: поДлине[0] ? поДлине[0].знаков + ' зн.: ' + поДлине[0].текст : 'нет',
      десятьСамыхДлинных: поДлине.slice(0, 10).map(
        (м) => м.знаков + (м.срезано ? ' СРЕЗАНО: ' : ' ok: ') + м.текст),
      срезанные: срезанные.map(
        (м) => 'ширина ' + м.ширинаЭкрана + ', нужно ' + м.нужноВысоты +
               ' точек высоты при отведённых ' + м.отведеноВысоты + ': ' + м.текст)
    };
    console.log(итог);
    return итог;
  }

  window.влезает = { записывать, стоп, забыть, померить, записать,
                     тыкатьВовсю, столИзНаходки, померитьЧужиеСтроки, отчёт,
                     всеСтроки: () => [...виденное.values()] };
  console.log('Замер готов. Зовите: влезает.записывать(), влезает.тыкатьВовсю(40), ' +
              'влезает.столИзНаходки(), влезает.отчёт().');
})();
