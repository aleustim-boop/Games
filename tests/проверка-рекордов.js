/* ---------------------------------------------------------------------
   Проверка 12. Облако молчит: рекорды всё равно приходят,
   и следующий раз к молчащему облаку не ходим
   --------------------------------------------------------------------- */

async function облакоМолчит() {
  const память = сделатьПамять(false);
  память.ящик['подкидной-дурак:рекорды'] = какТекст(6, [запись(6, '02.08.2026', 'лёгкий')]);
  const облако = сделатьОблако('молчит', '');
  const х = завестиХранилище(память, облако);

  const началось = Date.now();
  const р = await х.loadScore();
  const ждали = Date.now() - началось;

  проверить(р.таблица.length === 1 && р.таблица[0].очки === 6,
    '12. пока облако молчит, местные рекорды не показались: ' + таблицаСловами(р.таблица));
  проверить(ждали < 5000, '12. ждали облако ' + ждали + ' мс — это дольше разумного');

  // Связи нет — второй раз к облаку лезть незачем, иначе каждая победа снова
  // упрётся в ожидание. Смотрим, что обращений к облаку больше не было.
  const обращенийБыло = облако.обращений;
  const сноваНачалось = Date.now();
  const р2 = await х.loadScore();
  const сноваЖдали = Date.now() - сноваНачалось;

  проверить(облако.обращений === обращенийБыло,
    '12. после осечки игра снова полезла в молчащее облако (обращений было ' +
    обращенийБыло + ', стало ' + облако.обращений + ')');
  проверить(сноваЖдали < 300,
    '12. второе чтение опять ждало облако ' + сноваЖдали + ' мс вместо мгновенного ответа');
  проверить(р2.таблица.length === 1, '12. со второго раза рекорды не пришли');
}

