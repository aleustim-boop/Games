/* ---------------------------------------------------------------------
   Проверка 14. Две разные победы с одинаковыми очками и датой,
   но на разных уровнях — это два разных результата
   --------------------------------------------------------------------- */

async function разныеУровниПриСклейке() {
  const лёгкая = запись(3, '10.08.2026', 'лёгкий');
  const сложная = запись(3, '10.08.2026', 'сложный');
  const текст = какТекст(3, [лёгкая, сложная]);

  // Сначала без Telegram: склейки нет, обе строки обязаны сохраниться.
  // Это опорная точка — она показывает, что дело именно в склейке.
  const безОблака = завестиХранилище((function () {
    const п = сделатьПамять(false);
    п.ящик['подкидной-дурак:рекорды'] = текст;
    return п;
  })());
  const рБез = await безОблака.loadScore();
  проверить(рБез.таблица.length === 2,
    '14. без облака запись с другим уровнем потерялась ещё при чтении: ' + таблицаСловами(рБез.таблица));

  // А теперь то же самое, но игра открыта в Telegram и облако отвечает.
  const память = сделатьПамять(false);
  память.ящик['подкидной-дурак:рекорды'] = текст;
  const облако = сделатьОблако('работает', текст);
  const х = завестиХранилище(память, облако);

  const р = await х.loadScore();
  const пары = р.таблица.map(function (з) { return з.очки + ':' + з.сложность; });
  проверить(р.таблица.length === 2,
    '14. при склейке облака и памяти пропала запись с другим уровнем: было 2 строки, ' +
    'осталось ' + р.таблица.length + ' (' + JSON.stringify(пары) + '). Это два разных результата: ' +
    'серия из 3 побед на лёгком и такая же на сложном в один день. Причина — в js/telegram.js ' +
    'записи считаются одинаковыми по очкам и дате, без учёта уровня');
}

