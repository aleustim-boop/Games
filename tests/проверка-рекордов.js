/* =====================================================================
   Проверка таблицы рекордов без браузера.

   js/telegram.js написан для браузера, поэтому здесь мы подсовываем ему
   поддельный браузер: пустое окно (window) с поддельной памятью
   (localStorage). Никаких библиотек — только то, что есть в самом Node.

   Что проверяем:
     - первая победа попадает в таблицу с датой и уровнем соперника;
     - больше 10 строк не копится, лишние отсекаются;
     - лучшие строки стоят сверху;
     - «лучший» результат не теряется, даже когда строка выпала из десятки;
     - записи с разных уровней различимы (уровень хранится у каждой строки);
     - испорченная или чужая запись в памяти не роняет игру;
     - если память браузера запрещена — игра всё равно не падает.

   Запуск: node tests/проверка-рекордов.js
   ===================================================================== */

'use strict';

const fs = require('fs');
const vm = require('vm');
const path = require('path');

const ИСХОДНИК = fs.readFileSync(path.join(__dirname, '..', 'js', 'telegram.js'), 'utf8');

const беды = [];
let проверок = 0;

function проверить(условие, что) {
  проверок++;
  if (!условие) беды.push(что);
}

/* ---------------------------------------------------------------------
   Поддельный браузер
   --------------------------------------------------------------------- */

/** Память браузера понарошку. Можно сделать «запрещённой» — она будет ругаться. */
function сделатьПамять(запрещена) {
  const ящик = Object.create(null);
  return {
    ящик: ящик,
    getItem: function (ключ) {
      if (запрещена) throw new Error('память запрещена');
      return Object.prototype.hasOwnProperty.call(ящик, ключ) ? ящик[ключ] : null;
    },
    setItem: function (ключ, значение) {
      if (запрещена) throw new Error('память запрещена');
      ящик[ключ] = String(значение);
    },
    removeItem: function (ключ) {
      if (запрещена) throw new Error('память запрещена');
      delete ящик[ключ];
    }
  };
}

/**
 * Запустить js/telegram.js в поддельном браузере и вернуть его три функции.
 * Telegram не подсовываем: проверяем именно запасной путь — память браузера,
 * ровно так игра работает и в обычном браузере, и на GitHub Pages без Telegram.
 */
function завестиХранилище(память) {
  const окно = {
    localStorage: память,
    addEventListener: function () {},
    Promise: Promise,
    setTimeout: setTimeout,
    clearTimeout: clearTimeout
  };
  const песочница = {
    window: окно,
    document: { documentElement: { style: { setProperty: function () {} } } },
    Promise: Promise,
    setTimeout: setTimeout,
    clearTimeout: clearTimeout,
    JSON: JSON,
    Date: Date,
    Math: Math,
    Number: Number,
    String: String,
    Array: Array,
    Object: Object,
    Error: Error,
    isFinite: isFinite,
    console: console
  };
  песочница.globalThis = песочница;
  vm.createContext(песочница);
  vm.runInContext(ИСХОДНИК, песочница, { filename: 'js/telegram.js' });
  return { isReady: окно.isReady, saveScore: окно.saveScore, loadScore: окно.loadScore, память: память };
}

const ОЖИДАЕМАЯ_ДАТА = (function () {
  const с = new Date();
  const д = с.getDate(), м = с.getMonth() + 1;
  return (д < 10 ? '0' : '') + д + '.' + (м < 10 ? '0' : '') + м + '.' + с.getFullYear();
})();

/* ---------------------------------------------------------------------
   Проверка 1. Пустая таблица
   --------------------------------------------------------------------- */

async function пустаяТаблица() {
  const х = завестиХранилище(сделатьПамять(false));
  проверить(х.isReady() === true, '1. хранилище говорит, что не готово, хотя память браузера работает');
  const р = await х.loadScore();
  проверить(р && р.лучший === 0, '1. у нового игрока «лучший» не 0, а ' + (р && р.лучший));
  проверить(р && Array.isArray(р.таблица) && р.таблица.length === 0,
    '1. у нового игрока таблица не пуста');
}

/* ---------------------------------------------------------------------
   Проверка 2. Одна победа попадает в таблицу с датой и уровнем
   --------------------------------------------------------------------- */

async function однаПобеда() {
  const х = завестиХранилище(сделатьПамять(false));
  await х.saveScore(1, 'сложный');
  const р = await х.loadScore();
  проверить(р.таблица.length === 1, '2. после одной победы строк в таблице ' + р.таблица.length + ', а надо 1');
  проверить(р.таблица[0] && р.таблица[0].очки === 1, '2. записана не та длина серии: ' + JSON.stringify(р.таблица[0]));
  проверить(р.таблица[0] && р.таблица[0].сложность === 'сложный',
    '2. уровень соперника записан неверно: «' + (р.таблица[0] || {}).сложность + '»');
  проверить(р.таблица[0] && р.таблица[0].дата === ОЖИДАЕМАЯ_ДАТА,
    '2. дата записана неверно: «' + (р.таблица[0] || {}).дата + '», ожидалась «' + ОЖИДАЕМАЯ_ДАТА + '»');
  проверить(р.лучший === 1, '2. «лучший» после первой победы равен ' + р.лучший);
}

/* ---------------------------------------------------------------------
   Проверка 3. Серия побед подряд: 1, 2, 3 — и рекорд растёт
   --------------------------------------------------------------------- */

async function растущаяСерия() {
  const х = завестиХранилище(сделатьПамять(false));
  await х.saveScore(1, 'обычный');
  await х.saveScore(2, 'обычный');
  await х.saveScore(3, 'обычный');
  const р = await х.loadScore();
  проверить(р.лучший === 3, '3. после серии 1-2-3 «лучший» равен ' + р.лучший + ', а надо 3');
  const очки = р.таблица.map(function (з) { return з.очки; });
  проверить(JSON.stringify(очки) === JSON.stringify([3, 2, 1]),
    '3. строки лежат не по убыванию: ' + JSON.stringify(очки));
}

/* ---------------------------------------------------------------------
   Проверка 4. Больше 10 строк не копится, лучшие остаются
   --------------------------------------------------------------------- */

async function неБольшеДесяти() {
  const х = завестиХранилище(сделатьПамять(false));
  // 25 побед подряд — записей будет 25, а строк должно остаться 10.
  for (let i = 1; i <= 25; i++) await х.saveScore(i, 'обычный');
  const р = await х.loadScore();
  проверить(р.таблица.length === 10, '4. в таблице ' + р.таблица.length + ' строк вместо 10');
  проверить(р.лучший === 25, '4. «лучший» равен ' + р.лучший + ', а надо 25');
  const очки = р.таблица.map(function (з) { return з.очки; });
  проверить(JSON.stringify(очки) === JSON.stringify([25, 24, 23, 22, 21, 20, 19, 18, 17, 16]),
    '4. в десятке остались не лучшие строки: ' + JSON.stringify(очки));

  // И в памяти браузера тоже не больше десяти — иначе файл рекордов пухнет вечно.
  const сырое = JSON.parse(х.память.ящик['подкидной-дурак:рекорды']);
  проверить(сырое.таблица.length === 10,
    '4. в памяти браузера сохранено ' + сырое.таблица.length + ' строк вместо 10');
}

/* ---------------------------------------------------------------------
   Проверка 5. «Лучший» не теряется, когда строка выпала из десятки
   --------------------------------------------------------------------- */

async function лучшийНеТеряется() {
  const х = завестиХранилище(сделатьПамять(false));
  await х.saveScore(50, 'сложный');                       // разовый большой рекорд
  for (let i = 0; i < 12; i++) await х.saveScore(1, 'лёгкий');
  const р = await х.loadScore();
  проверить(р.лучший === 50, '5. «лучший» потерялся: ' + р.лучший + ' вместо 50');
  проверить(р.таблица[0] && р.таблица[0].очки === 50, '5. лучшая строка выпала из таблицы');
}

/* ---------------------------------------------------------------------
   Проверка 6. Уровни различимы
   --------------------------------------------------------------------- */

async function уровниРазличимы() {
  const х = завестиХранилище(сделатьПамять(false));
  await х.saveScore(3, 'лёгкий');
  await х.saveScore(2, 'сложный');
  await х.saveScore(1, 'обычный');
  const р = await х.loadScore();
  const пары = р.таблица.map(function (з) { return з.очки + ':' + з.сложность; });
  проверить(JSON.stringify(пары) === JSON.stringify(['3:лёгкий', '2:сложный', '1:обычный']),
    '6. уровни перепутались или потерялись: ' + JSON.stringify(пары));

  // Уровень не передали — должен подставиться «обычный», а не пустота.
  await х.saveScore(9);
  const р2 = await х.loadScore();
  проверить(р2.таблица[0].сложность === 'обычный',
    '6. без уровня записалось «' + р2.таблица[0].сложность + '» вместо «обычный»');
}

/* ---------------------------------------------------------------------
   Проверка 7. Испорченная запись в памяти
   --------------------------------------------------------------------- */

async function испорченнаяЗапись() {
  const мусор = [
    'это не json вообще',
    '{"таблица": "строка вместо списка"}',
    '[1,2,3]',
    'null',
    '{"лучший": "много", "таблица": [null, 5, {"очки": -7}, {"очки": "три"}]}',
    '{"таблица":[{"очки":2,"дата":123,"сложность":{}}]}'
  ];
  for (const текст of мусор) {
    const память = сделатьПамять(false);
    память.ящик['подкидной-дурак:рекорды'] = текст;
    const х = завестиХранилище(память);
    let р;
    try {
      р = await х.loadScore();
    } catch (ошибка) {
      беды.push('7. чтение испорченной записи ' + JSON.stringify(текст) + ' упало: ' + ошибка.message);
      continue;
    }
    проверок++;
    if (!р || typeof р.лучший !== 'number' || !Array.isArray(р.таблица)) {
      беды.push('7. на испорченной записи ' + JSON.stringify(текст) + ' вернулось непонятное: ' + JSON.stringify(р));
      continue;
    }
    for (const з of р.таблица) {
      if (typeof з.очки !== 'number' || !isFinite(з.очки) || з.очки < 0) {
        беды.push('7. из мусора ' + JSON.stringify(текст) + ' пролезли очки: ' + JSON.stringify(з));
      }
      if (typeof з.сложность !== 'string' || !з.сложность) {
        беды.push('7. из мусора ' + JSON.stringify(текст) + ' пролез пустой уровень: ' + JSON.stringify(з));
      }
      if (typeof з.дата !== 'string') {
        беды.push('7. из мусора ' + JSON.stringify(текст) + ' пролезла нечитаемая дата: ' + JSON.stringify(з));
      }
    }
    // После порчи запись должна снова стать нормальной.
    try {
      await х.saveScore(4, 'обычный');
      const после = await х.loadScore();
      проверок++;
      if (после.лучший < 4) беды.push('7. после порчи ' + JSON.stringify(текст) + ' новый рекорд не записался');
    } catch (ошибка) {
      беды.push('7. запись после порчи ' + JSON.stringify(текст) + ' упала: ' + ошибка.message);
    }
  }
}

/* ---------------------------------------------------------------------
   Проверка 8. Запрещённая память браузера
   --------------------------------------------------------------------- */

async function памятьЗапрещена() {
  let х;
  try {
    х = завестиХранилище(сделатьПамять(true));
  } catch (ошибка) {
    беды.push('8. при запрещённой памяти сам файл telegram.js упал: ' + ошибка.message);
    return;
  }
  проверить(х.isReady() === false, '8. при запрещённой памяти хранилище утверждает, что готово');
  try {
    const р = await х.loadScore();
    проверить(р && р.таблица.length === 0, '8. при запрещённой памяти чтение вернуло что-то странное');
    const после = await х.saveScore(5, 'обычный');
    проверить(после && typeof после.лучший === 'number',
      '8. при запрещённой памяти запись вернула не объект рекордов');
  } catch (ошибка) {
    беды.push('8. при запрещённой памяти работа с рекордами упала: ' + ошибка.message);
  }
}

/* ---------------------------------------------------------------------
   Проверка 9. Мусорные очки при записи
   --------------------------------------------------------------------- */

async function мусорныеОчки() {
  const х = завестиХранилище(сделатьПамять(false));
  for (const значение of [undefined, null, -5, NaN, Infinity, '7', 2.7, {}, 'три']) {
    try {
      await х.saveScore(значение, 'обычный');
    } catch (ошибка) {
      беды.push('9. saveScore(' + String(значение) + ') упала: ' + ошибка.message);
    }
  }
  const р = await х.loadScore();
  проверок++;
  for (const з of р.таблица) {
    if (!Number.isInteger(з.очки) || з.очки < 0) {
      беды.push('9. в таблицу пролезли кривые очки: ' + JSON.stringify(з));
    }
  }
  проверить(р.лучший === 7, '9. из мусора «лучший» вышел ' + р.лучший + ', а по-хорошему 7 (строка "7")');
}

/* ---------------------------------------------------------------------
   Запуск
   --------------------------------------------------------------------- */

(async function () {
  console.log('=== Проверка таблицы рекордов (без браузера) ===\n');
  await пустаяТаблица();
  await однаПобеда();
  await растущаяСерия();
  await неБольшеДесяти();
  await лучшийНеТеряется();
  await уровниРазличимы();
  await испорченнаяЗапись();
  await памятьЗапрещена();
  await мусорныеОчки();

  console.log('проверок сделано: ' + проверок);
  if (беды.length === 0) {
    console.log('=== Итог: рекорды ведут себя правильно ===');
    process.exit(0);
  }
  console.log('НАЙДЕНО:');
  беды.forEach(function (т) { console.log('  - ' + т); });
  console.log('=== Итог: бед ' + беды.length + ' ===');
  process.exit(1);
})();
