/* =====================================================================
   Проверка таблицы рекордов без браузера.

   js/telegram.js написан для браузера, поэтому здесь мы подсовываем ему
   поддельный браузер: пустое окно (window) с поддельной памятью
   (localStorage), а где нужно — и поддельное облако Telegram.
   Никаких библиотек — только то, что есть в самом Node.

   КАК СЕЙЧАС УСТРОЕНА ЗАПИСЬ СЕРИИ (по решению штаба).
   Игра сообщает результат после каждой победы: 1, 2, 3… Раньше на каждое
   такое сообщение заводилась новая строка, и серия из десяти побед занимала
   всю таблицу ступеньками «10 подряд», «9», «8»… Теперь если пришёл
   результат ровно на одну победу больше и уровень тот же — растёт уже
   существующая строка. Серия любой длины занимает одну строку.

   Что проверяем:
     - первая победа попадает в таблицу с датой и уровнем соперника;
     - серия побед подряд занимает ОДНУ строку и растёт;
     - новая серия (после проигрыша) заводит отдельную строку;
     - серия на другом уровне не сливается с чужой;
     - больше 10 строк не копится, в десятке остаются лучшие;
     - «лучший» результат не теряется, даже когда строка выпала из десятки;
     - записи с разных уровней различимы;
     - испорченная или чужая запись в памяти не роняет игру;
     - если память браузера запрещена — игра всё равно не падает;
     - облако и память браузера СКЛАДЫВАЮТСЯ: победа, добытая без связи,
       не пропадает, когда облако снова отвечает.

   Запуск: node tests/проверка-рекордов.js
   ===================================================================== */

'use strict';

const fs = require('fs');
const vm = require('vm');
const path = require('path');

const ИСХОДНИК = fs.readFileSync(path.join(__dirname, '..', 'js', 'telegram.js'), 'utf8');

const беды = [];
let проверок = 0;

function проверить(условие, что) {
  проверок++;
  if (!условие) беды.push(что);
}

/* ---------------------------------------------------------------------
   Поддельный браузер
   --------------------------------------------------------------------- */

/** Память браузера понарошку. Можно сделать «запрещённой» — она будет ругаться. */
function сделатьПамять(запрещена) {
  const ящик = Object.create(null);
  return {
    ящик: ящик,
    getItem: function (ключ) {
      if (запрещена) throw new Error('память запрещена');
      return Object.prototype.hasOwnProperty.call(ящик, ключ) ? ящик[ключ] : null;
    },
    setItem: function (ключ, значение) {
      if (запрещена) throw new Error('память запрещена');
      ящик[ключ] = String(значение);
    },
    removeItem: function (ключ) {
      if (запрещена) throw new Error('память запрещена');
      delete ящик[ключ];
    }
  };
}

/**
 * Поддельное облако Telegram.
 * поведение: 'работает' — отвечает как надо;
 *            'молчит'   — не отвечает никогда (так выглядит пропавшая связь);
 *            'отказывает' — отвечает ошибкой.
 * Считает обращения — по ним видно, ходили к облаку или нет.
 */
function сделатьОблако(поведение, начальныйТекст) {
  const это = { текст: начальныйТекст || '', обращений: 0 };
  это.облако = {
    getItem: function (ключ, ответить) {
      это.обращений++;
      if (поведение === 'молчит') return;
      if (поведение === 'отказывает') { ответить('облако сломалось'); return; }
      ответить(null, это.текст);
    },
    setItem: function (ключ, текст, ответить) {
      это.обращений++;
      if (поведение === 'молчит') return;
      if (поведение === 'отказывает') { ответить('облако сломалось'); return; }
      это.текст = текст;
      ответить(null, true);
    }
  };
  return это;
}

/** Запись рекордов в том виде, в каком она лежит в хранилище. */
function запись(очки, дата, сложность) {
  return { очки: очки, дата: дата, сложность: сложность };
}

function какТекст(лучший, таблица) {
  return JSON.stringify({ лучший: лучший, таблица: таблица });
}

/**
 * Запустить js/telegram.js в поддельном браузере и вернуть его три функции.
 * Облако по умолчанию не подставляем: это обычный браузер без Telegram,
 * ровно так игра работает на GitHub Pages.
 */
function завестиХранилище(память, облако) {
  const окно = {
    localStorage: память,
    addEventListener: function () {}
  };
  const песочница = {
    window: окно,
    document: {
      documentElement: {
        style: { setProperty: function () {}, removeProperty: function () {} }
      }
    },
    Promise: Promise,
    setTimeout: setTimeout,
    clearTimeout: clearTimeout,
    JSON: JSON,
    Date: Date,
    Math: Math,
    Number: Number,
    String: String,
    Array: Array,
    Object: Object,
    Error: Error,
    isFinite: isFinite,
    console: console
  };
  песочница.globalThis = песочница;

  /** Подключить или убрать облако прямо во время работы — как будто игрок
      открыл игру в Telegram или, наоборот, потерял связь. */
  function подключитьОблако(это) {
    окно.Telegram = { WebApp: {
      CloudStorage: это.облако,
      isVersionAtLeast: function () { return true; },
      ready: function () {},
      expand: function () {},
      onEvent: function () {},
      themeParams: {}
    } };
  }
  function отключитьОблако() { delete окно.Telegram; }

  if (облако) подключитьОблако(облако);

  vm.createContext(песочница);
  vm.runInContext(ИСХОДНИК, песочница, { filename: 'js/telegram.js' });

  return {
    isReady: окно.isReady, saveScore: окно.saveScore, loadScore: окно.loadScore,
    память: память, подключитьОблако: подключитьОблако, отключитьОблако: отключитьОблако
  };
}

const ОЖИДАЕМАЯ_ДАТА = (function () {
  const с = new Date();
  const д = с.getDate(), м = с.getMonth() + 1;
  return (д < 10 ? '0' : '') + д + '.' + (м < 10 ? '0' : '') + м + '.' + с.getFullYear();
})();

/**
 * Сыграть серию побед подряд.
 * Игра сообщает результат после КАЖДОЙ победы: 1, 2, 3… — так это и делаем.
 */
async function сыгратьСерию(х, длина, уровень) {
  for (let победа = 1; победа <= длина; победа++) await х.saveScore(победа, уровень);
}

/** Короткая запись таблицы для сообщений об ошибке: «3 обычный, 2 сложный». */
function таблицаСловами(таблица) {
  return таблица.map(function (з) { return з.очки + ' ' + з.сложность; }).join(', ');
}

/* ---------------------------------------------------------------------
   Проверка 1. Пустая таблица
   --------------------------------------------------------------------- */

async function пустаяТаблица() {
  const х = завестиХранилище(сделатьПамять(false));
  проверить(х.isReady() === true, '1. хранилище говорит, что не готово, хотя память браузера работает');
  const р = await х.loadScore();
  проверить(р && р.лучший === 0, '1. у нового игрока «лучший» не 0, а ' + (р && р.лучший));
  проверить(р && Array.isArray(р.таблица) && р.таблица.length === 0,
    '1. у нового игрока таблица не пуста');
}

/* ---------------------------------------------------------------------
   Проверка 2. Одна победа попадает в таблицу с датой и уровнем
   --------------------------------------------------------------------- */

async function однаПобеда() {
  const х = завестиХранилище(сделатьПамять(false));
  await х.saveScore(1, 'сложный');
  const р = await х.loadScore();
  проверить(р.таблица.length === 1, '2. после одной победы строк в таблице ' + р.таблица.length + ', а надо 1');
  проверить(р.таблица[0] && р.таблица[0].очки === 1, '2. записана не та длина серии: ' + JSON.stringify(р.таблица[0]));
  проверить(р.таблица[0] && р.таблица[0].сложность === 'сложный',
    '2. уровень соперника записан неверно: «' + (р.таблица[0] || {}).сложность + '»');
  проверить(р.таблица[0] && р.таблица[0].дата === ОЖИДАЕМАЯ_ДАТА,
    '2. дата записана неверно: «' + (р.таблица[0] || {}).дата + '», ожидалась «' + ОЖИДАЕМАЯ_ДАТА + '»');
  проверить(р.лучший === 1, '2. «лучший» после первой победы равен ' + р.лучший);
}

/* ---------------------------------------------------------------------
   Проверка 3. Серия побед подряд занимает ОДНУ строку и растёт
   --------------------------------------------------------------------- */

async function растущаяСерия() {
  const х = завестиХранилище(сделатьПамять(false));

  // Три победы подряд — это один результат, а не три.
  await сыгратьСерию(х, 3, 'обычный');
  let р = await х.loadScore();
  проверить(р.таблица.length === 1,
    '3. серия из трёх побед заняла ' + р.таблица.length + ' строк вместо одной: ' + таблицаСловами(р.таблица));
  проверить(р.таблица[0] && р.таблица[0].очки === 3,
    '3. в строке серии не 3 победы: ' + JSON.stringify(р.таблица[0]));
  проверить(р.лучший === 3, '3. после серии из трёх побед «лучший» равен ' + р.лучший + ', а надо 3');

  // Проигрыш обрывает серию. Следующая серия — отдельная строка.
  await сыгратьСерию(х, 2, 'обычный');
  р = await х.loadScore();
  проверить(р.таблица.length === 2,
    '3. вторая серия не завела свою строку: строк ' + р.таблица.length + ' — ' + таблицаСловами(р.таблица));
  проверить(JSON.stringify(р.таблица.map(function (з) { return з.очки; })) === JSON.stringify([3, 2]),
    '3. строки двух серий легли неверно: ' + таблицаСловами(р.таблица));

  // Серия на другом уровне не должна прирасти к чужой строке.
  await сыгратьСерию(х, 2, 'сложный');
  р = await х.loadScore();
  проверить(р.таблица.length === 3,
    '3. серия на другом уровне слилась с чужой: строк ' + р.таблица.length + ' — ' + таблицаСловами(р.таблица));
  const уровни = р.таблица.map(function (з) { return з.очки + ':' + з.сложность; });
  проверить(JSON.stringify(уровни) === JSON.stringify(['3:обычный', '2:обычный', '2:сложный']),
    '3. строки разных уровней перепутались: ' + JSON.stringify(уровни));

  // Результат «через одну» — это уже не продолжение, а новая строка.
  const у = завестиХранилище(сделатьПамять(false));
  await у.saveScore(3, 'обычный');
  await у.saveScore(5, 'обычный');
  const р2 = await у.loadScore();
  проверить(р2.таблица.length === 2,
    '3. результат 5 после 3 прирос к чужой строке вместо новой: ' + таблицаСловами(р2.таблица));
}

/* ---------------------------------------------------------------------
   Проверка 4. Больше 10 строк не копится, лучшие остаются

   Раньше таблицу переполняли одной длинной серией — теперь она занимает
   одну строку, поэтому набор данных другой: много РАЗНЫХ серий.
   Само ограничение никуда не делось, его и проверяем.
   --------------------------------------------------------------------- */

async function неБольшеДесяти() {
  const х = завестиХранилище(сделатьПамять(false));

  // Тринадцать разных серий: сначала десять длинных, потом три коротких.
  for (let длина = 25; длина >= 16; длина--) await сыгратьСерию(х, длина, 'обычный');
  for (const длина of [5, 3, 2]) await сыгратьСерию(х, длина, 'обычный');

  const р = await х.loadScore();
  проверить(р.таблица.length === 10, '4. в таблице ' + р.таблица.length + ' строк вместо 10');
  проверить(р.лучший === 25, '4. «лучший» равен ' + р.лучший + ', а надо 25');
  const очки = р.таблица.map(function (з) { return з.очки; });
  проверить(JSON.stringify(очки) === JSON.stringify([25, 24, 23, 22, 21, 20, 19, 18, 17, 16]),
    '4. в десятке остались не лучшие строки: ' + JSON.stringify(очки));

  // И в памяти браузера тоже не больше десяти — иначе файл рекордов пухнет вечно.
  const сырое = JSON.parse(х.память.ящик['подкидной-дурак:рекорды']);
  проверить(сырое.таблица.length === 10,
    '4. в памяти браузера сохранено ' + сырое.таблица.length + ' строк вместо 10');
}

/* ---------------------------------------------------------------------
   Проверка 5. «Лучший» не теряется, когда строка выпала из десятки
   --------------------------------------------------------------------- */

async function лучшийНеТеряется() {
  const х = завестиХранилище(сделатьПамять(false));
  await х.saveScore(50, 'сложный');                       // разовый большой рекорд
  for (let i = 0; i < 12; i++) await х.saveScore(1, 'лёгкий');
  const р = await х.loadScore();
  проверить(р.лучший === 50, '5. «лучший» потерялся: ' + р.лучший + ' вместо 50');
  проверить(р.таблица[0] && р.таблица[0].очки === 50, '5. лучшая строка выпала из таблицы');
}

/* ---------------------------------------------------------------------
   Проверка 6. Уровни различимы
   --------------------------------------------------------------------- */

async function уровниРазличимы() {
  const х = завестиХранилище(сделатьПамять(false));
  await х.saveScore(3, 'лёгкий');
  await х.saveScore(2, 'сложный');
  await х.saveScore(1, 'обычный');
  const р = await х.loadScore();
  const пары = р.таблица.map(function (з) { return з.очки + ':' + з.сложность; });
  проверить(JSON.stringify(пары) === JSON.stringify(['3:лёгкий', '2:сложный', '1:обычный']),
    '6. уровни перепутались или потерялись: ' + JSON.stringify(пары));

  // Уровень не передали — должен подставиться «обычный», а не пустота.
  await х.saveScore(9);
  const р2 = await х.loadScore();
  проверить(р2.таблица[0].сложность === 'обычный',
    '6. без уровня записалось «' + р2.таблица[0].сложность + '» вместо «обычный»');
}

/* ---------------------------------------------------------------------
   Проверка 7. Испорченная запись в памяти
   --------------------------------------------------------------------- */

async function испорченнаяЗапись() {
  const мусор = [
    'это не json вообще',
    '{"таблица": "строка вместо списка"}',
    '[1,2,3]',
    'null',
    '{"лучший": "много", "таблица": [null, 5, {"очки": -7}, {"очки": "три"}]}',
    '{"таблица":[{"очки":2,"дата":123,"сложность":{}}]}'
  ];
  for (const текст of мусор) {
    const память = сделатьПамять(false);
    память.ящик['подкидной-дурак:рекорды'] = текст;
    const х = завестиХранилище(память);
    let р;
    try {
      р = await х.loadScore();
    } catch (ошибка) {
      беды.push('7. чтение испорченной записи ' + JSON.stringify(текст) + ' упало: ' + ошибка.message);
      continue;
    }
    проверок++;
    if (!р || typeof р.лучший !== 'number' || !Array.isArray(р.таблица)) {
      беды.push('7. на испорченной записи ' + JSON.stringify(текст) + ' вернулось непонятное: ' + JSON.stringify(р));
      continue;
    }
    for (const з of р.таблица) {
      if (typeof з.очки !== 'number' || !isFinite(з.очки) || з.очки < 0) {
        беды.push('7. из мусора ' + JSON.stringify(текст) + ' пролезли очки: ' + JSON.stringify(з));
      }
      if (typeof з.сложность !== 'string' || !з.сложность) {
        беды.push('7. из мусора ' + JSON.stringify(текст) + ' пролез пустой уровень: ' + JSON.stringify(з));
      }
      if (typeof з.дата !== 'string') {
        беды.push('7. из мусора ' + JSON.stringify(текст) + ' пролезла нечитаемая дата: ' + JSON.stringify(з));
      }
    }
    // После порчи запись должна снова стать нормальной.
    try {
      await х.saveScore(4, 'обычный');
      const после = await х.loadScore();
      проверок++;
      if (после.лучший < 4) беды.push('7. после порчи ' + JSON.stringify(текст) + ' новый рекорд не записался');
    } catch (ошибка) {
      беды.push('7. запись после порчи ' + JSON.stringify(текст) + ' упала: ' + ошибка.message);
    }
  }
}

/* ---------------------------------------------------------------------
   Проверка 8. Запрещённая память браузера
   --------------------------------------------------------------------- */

async function памятьЗапрещена() {
  let х;
  try {
    х = завестиХранилище(сделатьПамять(true));
  } catch (ошибка) {
    беды.push('8. при запрещённой памяти сам файл telegram.js упал: ' + ошибка.message);
    return;
  }
  проверить(х.isReady() === false, '8. при запрещённой памяти хранилище утверждает, что готово');
  try {
    const р = await х.loadScore();
    проверить(р && р.таблица.length === 0, '8. при запрещённой памяти чтение вернуло что-то странное');
    const после = await х.saveScore(5, 'обычный');
    проверить(после && typeof после.лучший === 'number',
      '8. при запрещённой памяти запись вернула не объект рекордов');
  } catch (ошибка) {
    беды.push('8. при запрещённой памяти работа с рекордами упала: ' + ошибка.message);
  }
}

/* ---------------------------------------------------------------------
   Проверка 9. Мусорные очки при записи
   --------------------------------------------------------------------- */

async function мусорныеОчки() {
  const х = завестиХранилище(сделатьПамять(false));
  for (const значение of [undefined, null, -5, NaN, Infinity, '7', 2.7, {}, 'три']) {
    try {
      await х.saveScore(значение, 'обычный');
    } catch (ошибка) {
      беды.push('9. saveScore(' + String(значение) + ') упала: ' + ошибка.message);
    }
  }
  const р = await х.loadScore();
  проверок++;
  for (const з of р.таблица) {
    if (!Number.isInteger(з.очки) || з.очки < 0) {
      беды.push('9. в таблицу пролезли кривые очки: ' + JSON.stringify(з));
    }
  }
  проверить(р.лучший === 7, '9. из мусора «лучший» вышел ' + р.лучший + ', а по-хорошему 7 (строка "7")');
}

/* ---------------------------------------------------------------------
   Проверка 10. Победа без связи не теряется

   Самое свежее в файле: облако и память браузера не спорят, а складываются.
   Играли без Telegram — победа легла только в память телефона. Открыли
   игру в Telegram — она обязана остаться, а не пропасть под облачной копией.
   --------------------------------------------------------------------- */

async function победаБезСвязиНеТеряется() {
  const х = завестиХранилище(сделатьПамять(false));

  // Играем без Telegram: облака нет вовсе.
  await х.saveScore(4, 'обычный');
  const местные = await х.loadScore();
  проверить(местные.таблица.length === 1, '10. победа без связи не записалась в память браузера');

  // Открыли игру в Telegram: в облаке лежит своя, более старая победа.
  const облако = сделатьОблако('работает', какТекст(7, [запись(7, '01.01.2026', 'сложный')]));
  х.подключитьОблако(облако);

  const вместе = await х.loadScore();
  const очки = вместе.таблица.map(function (з) { return з.очки; });
  проверить(вместе.таблица.length === 2,
    '10. после появления связи строк ' + вместе.таблица.length + ', а надо 2 (облачная и местная): ' +
    таблицаСловами(вместе.таблица));
  проверить(очки.indexOf(4) !== -1, '10. ПОБЕДА БЕЗ СВЯЗИ ПРОПАЛА: в таблице ' + JSON.stringify(очки));
  проверить(очки.indexOf(7) !== -1, '10. облачная запись пропала: в таблице ' + JSON.stringify(очки));
  проверить(вместе.лучший === 7, '10. «лучший» после склейки равен ' + вместе.лучший + ', а надо 7');
}

