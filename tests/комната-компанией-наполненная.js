async function собратьСтол(страница, размер, парами) {
  const мест = парами ? 4 : 6;
  const создание = await запрос('/создать', { имя: ДЛИННОЕ_ИМЯ, мест: мест, парами: парами });
  if (!создание.код) throw new Error('комнату завести не вышло');
  const код = создание.код;

  /* Живой игрок — страница в браузере. Входит по коду, как человек. */
  await страница.click('#кнопка-игра-дурак'); await спать(250);
  await страница.click('#кнопка-с-другом'); await спать(400);
  await страница.click('#кнопка-войти-по-коду'); await спать(400);
  await страница.fill('#поле-кода', код);
  await страница.click('#кнопка-войти');
  await спать(1500);

  /* Ещё один живой — он потом выйдет, чтобы появилось место «ушёл». */
  const уходящий = await запрос('/войти', { код: код, имя: 'Аня' });

  /* Остальные места занимают боты. */
  let ботов = 0;
  for (let i = 0; i < мест; i++) {
    const о = await запрос('/ход', { код: код, пропуск: создание.пропуск, действие: 'бот' });
    if (!о.принято) break;
    ботов++;
  }
  console.log('  стол на ' + мест + ' мест: хозяин с длинным именем, страница, Аня и ботов ' + ботов);

  await спать(800);
  /* Уходящего оставляем за столом: в прихожей его место просто освободилось бы
     и стало «Свободное место». Место «выбыл» бывает уже в партии — поэтому
     он выйдет после начала, см. ниже. */
  return { код: код, пропуск: создание.пропуск, уходящий: уходящий.пропуск };
}

(async () => {
  console.log('Комната компанией. Страницы: ' + ПОРТ_СТРАНИЦ + ', комнаты: ' + ПОРТ_КОМНАТ);
  const браузер = await chromium.launch();

  /* ---- 1. Стол на шесть мест, три ширины ---- */
  for (const размер of [{ ш: 390, в: 844 }, { ш: 360, в: 640 }, { ш: 320, в: 568 }]) {
    console.log('\n=== Шесть мест, ' + размер.ш + '×' + размер.в + ' ===');
    const окно = await браузер.newContext({ viewport: { width: размер.ш, height: размер.в }, hasTouch: true, deviceScaleFactor: 2 });
    const страница = await окно.newPage();
    const красные = [];
    страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
    страница.on('console', (м) => {
      if (м.type() !== 'error') return;
      const откуда = (м.location && м.location() && м.location().url) || '';
      if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
      красные.push('консоль: ' + м.text());
    });
    await подготовитьПодделку(страница, { версия: '8.0', полныйЭкран: 'дают' });
    await страница.goto('http://127.0.0.1:' + ПОРТ_СТРАНИЦ + '/?сервер=http://127.0.0.1:' + ПОРТ_КОМНАТ);
    await спать(600);

    const стол = await собратьСтол(страница, размер, false);
    const видно = await осмотретьКомнату(страница);

    console.log('  экран «' + видно.экран + '»: мест видно ' + видно.мест + ', своих ' + видно.своих +
      ', ботов ' + видно.ботов + ', ушедших ' + видно.ушедших);
    видно.места.forEach((м) => console.log('     · [' + м.класс + '] ' + м.текст));

    проверить(видно.мест >= 6, 'на экране видно все шесть мест: ' + видно.мест);
    console.log('  (в прихожей ушедших нет и быть не должно: место просто освобождается —' +
      ' «выбыл» бывает уже в партии, смотрим ниже)');
    проверить(видно.ботов >= 1, 'боты за столом обозначены: ' + видно.ботов);
    проверить(видно.ширинаСтраницы <= видно.ширинаОкна + 1,
      'длинное имя не растянуло страницу вбок: ' + видно.ширинаСтраницы + ' при ' + видно.ширинаОкна);
    if (видно.своих) {
      console.log('  свой карман: ' + видно.свойГде + ', прокрутка экрана ' + видно.прокруткаЭкрана + 'px');
      проверить(видно.свойВиден === true, 'свой карман виден без прокрутки (' + видно.свойГде + ')');
    } else {
      console.log('  (свой карман приметами не опознан — проверить видимость нечем)');
    }
    проверить(красные.length === 0, 'консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));

    await страница.screenshot({ path: ПАПКА_СНИМКОВ + 'комната-шесть-мест-' + размер.ш + '.png', fullPage: true });
    console.log('  снимок: ' + ПАПКА_СНИМКОВ + 'комната-шесть-мест-' + размер.ш + '.png');

    /* На узком телефоне заодно смотрим стол в игре: видно ли, чей ход. */
    if (размер.ш === 320) {
      const начали = await запрос('/ход', { код: стол.код, пропуск: стол.пропуск, действие: 'начать' });
      await спать(1200);
      /* Теперь один живой выходит прямо из партии — так появляется место
         выбывшего рядом с живыми, ради которого всё и затевалось. */
      if (стол.уходящий) { await запрос('/выйти', { код: стол.код, пропуск: стол.уходящий }); await спать(1500); }
      const вИгре = await осмотретьКомнату(страница);
      console.log('  партия начата: ' + (начали.принято ? 'да' : 'нет — ' + начали.причина) +
        ', экран «' + вИгре.экран + '», подсказка: «' + вИгре.ходСловами.trim().slice(0, 60) + '»');
      console.log('  за столом: мест ' + вИгре.мест + ', выбывших ' + вИгре.ушедших);
      вИгре.места.forEach((м) => console.log('     · [' + м.класс + '] ' + м.текст));
      проверить(вИгре.ушедших >= 1,
        'место выбывшего показано отдельным видом рядом с живыми: ' + вИгре.ушедших);
      проверить(вИгре.ходСловами.trim().length > 0,
        'на узком экране видно словами, чей сейчас ход: «' + вИгре.ходСловами.trim().slice(0, 40) + '»');
      await страница.screenshot({ path: ПАПКА_СНИМКОВ + 'стол-вшестером-320.png', fullPage: true });
      console.log('  снимок: ' + ПАПКА_СНИМКОВ + 'стол-вшестером-320.png');
    }
    await окно.close();
  }

  /* ---- 2. Игра парами ---- */
  console.log('\n=== Игра парами, 390×844 ===');
  {
    const окно = await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, deviceScaleFactor: 2 });
    const страница = await окно.newPage();
    await подготовитьПодделку(страница, { версия: '8.0', полныйЭкран: 'дают' });
    await страница.goto('http://127.0.0.1:' + ПОРТ_СТРАНИЦ + '/?сервер=http://127.0.0.1:' + ПОРТ_КОМНАТ);
    await спать(600);
    await собратьСтол(страница, { ш: 390, в: 844 }, true);
    const видно = await осмотретьКомнату(страница);
    console.log('  мест ' + видно.мест + ', напарники помечены у ' + видно.напарников + ' мест');
    видно.места.forEach((м) => console.log('     · ' + м.текст));
    проверить(видно.мест >= 4, 'парный стол собран: мест ' + видно.мест);
    проверить(видно.напарников >= 1, 'напарники на экране помечены: ' + видно.напарников);
    await страница.screenshot({ path: ПАПКА_СНИМКОВ + 'комната-парами-390.png', fullPage: true });
    console.log('  снимок: ' + ПАПКА_СНИМКОВ + 'комната-парами-390.png');
    await окно.close();
  }

  await браузер.close();
  console.log('\nИтог: провалов ' + провалов);
  process.exit(провалов ? 1 : 0);
})().catch((о) => { console.error('Стенд упал: ' + (о && о.stack || о)); process.exit(2); });
