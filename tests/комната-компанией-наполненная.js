const http = require('http');
const { chromium, подготовитьПодделку } = require('./браузер-робот.js');

const ПОРТ_СТРАНИЦ = Number(process.argv[2]) || 8080;
const ПОРТ_КОМНАТ = Number(process.argv[3]) || 8817;
const ХОСТ = '127.0.0.1';
const ПАПКА_СНИМКОВ = 'tests/скриншоты/';

const ДЛИННОЕ_ИМЯ = 'Пал Палыч Загогулинский-Задунайский';

let провалов = 0;
function проверить(условие, слова) {
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}

const спать = (мс) => new Promise((ф) => setTimeout(ф, мс));

function запрос(путь, тело) {
  return new Promise(function (готово, беда) {
    const текст = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const о = http.request({
      host: ХОСТ, port: ПОРТ_КОМНАТ, method: 'POST', path: encodeURI(путь),
      headers: { 'Content-Type': 'application/json', 'Content-Length': текст.length }
    }, function (ответ) {
      let к = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (ч) { к += ч; });
      ответ.on('end', function () { try { готово(JSON.parse(к)); } catch (сбой) { готово({}); } });
    });
    о.on('error', беда);
    о.end(текст);
  });
}

/** Что видно на экране комнаты: места, имена, свой карман, кто ушёл. */
async function осмотретьКомнату(страница) {
  return страница.evaluate(() => {
    const видимыеЭкраны = document.querySelectorAll('.экран.экран--виден');
    const экран = видимыеЭкраны[видимыеЭкраны.length - 1];
    /* Места ищем по настоящей примете разметки — слову «место» в классе.
       Если примета поменяется, стенд скажет «мест 0», а не соврёт числом. */
    /* В прихожей места — карточки со словом «место» в классе. За столом
       разметка другая: там плашки соперников. Поэтому две приметы, а не
       одна: иначе за столом стенд насчитает «мест 0» и промолчит о выбывшем. */
    let приметы = '[class*="место"]';
    if (экран.querySelectorAll(приметы).length === 0) приметы = '[class*="соперник"], [class*="игрок"], [class*="плашка-места"]';
    const всеКусочки = [...экран.querySelectorAll(приметы)]
      .filter((у) => у.offsetParent !== null && у.getBoundingClientRect().height > 8);
    /* Внутри карточки места лежат свои кусочки с тем же словом в классе
       (номер, имя, пометка). Считаем только внешние: иначе шесть мест
       превращаются в двадцать пять, и число врёт. */
    const места = всеКусочки.filter((у) => !всеКусочки.some((другой) => другой !== у && другой.contains(у)));
    const текст = (у) => (у.textContent || '').replace(/\s+/g, ' ').trim();
    /* Свой карман страница подписывает «— вы»; класс тоже смотрим,
       чтобы примета не держалась на одном слове. */
    /* Осторожно с «\b» в русских словах: в JavaScript граница слова считается
       по латинице, и «--я\b» НЕ совпадает с классом «место-за-столом--я».
       На этом стенд уже один раз соврал «своих 0», хотя своё место было
       выделено. Поэтому проверяем конец строки явно. */
    const свой = места.filter((у) => /--я($|[^а-яёa-z])/i.test(у.className) ||
      /--сво|это-я/i.test(у.className) || /—\s*вы(\s|$)|\(вы\)|это вы/i.test(текст(у)));
    const ушедшие = места.filter((у) => /ушёл|ушел|вышел|выбыл/i.test(текст(у) + ' ' + у.className));
    const боты = места.filter((у) => /бот/i.test(текст(у) + ' ' + у.className));
    const напарники = места.filter((у) => /напарник|пара|вместе/i.test(текст(у) + ' ' + у.className));
    const края = места.map((у) => {
      const к = у.getBoundingClientRect();
      return { верх: Math.round(к.top), низ: Math.round(к.bottom), ш: Math.round(к.width), класс: у.className, текст: текст(у).slice(0, 40) };
    });
    const мойКарман = свой.length ? свой[0].getBoundingClientRect() : null;
    return {
      экран: экран.id,
      мест: места.length,
      своих: свой.length,
      ушедших: ушедшие.length,
      ботов: боты.length,
      напарников: напарники.length,
      места: края,
      свойВиден: мойКарман ? (мойКарман.top >= -1 && мойКарман.bottom <= window.innerHeight + 1) : null,
      свойГде: мойКарман ? Math.round(мойКарман.top) + '…' + Math.round(мойКарман.bottom) : '',
      прокруткаЭкрана: Math.max(0, экран.scrollHeight - экран.clientHeight),
      окно: window.innerHeight,
      ширинаСтраницы: document.documentElement.scrollWidth,
      ширинаОкна: window.innerWidth,
      ходСловами: (document.getElementById('подсказка-текст') || {}).textContent || ''
    };
  });
}

