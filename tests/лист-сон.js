function создатьЭлемент(тег, реестр, журнал) {
  const классы = new Set();
  const слушатели = {};
  const атрибуты = {};
  let свойТекст = '';
  let _id = '';
  const эл = {
    tagName: тег.toUpperCase(),
    children: [],
    parentNode: null,
    disabled: false,
    записейТекста: 0,   // сколько раз писали в textContent (плашка — живая область, лишние записи читает чтец экрана)
    classList: {
      add: function (к) { классы.add(к); },
      remove: function (к) { классы.delete(к); },
      contains: function (к) { return классы.has(к); },
      toggle: function (к, надо) {
        const нужно = надо === undefined ? !классы.has(к) : Boolean(надо);
        if (нужно) классы.add(к); else классы.delete(к);
      }
    },
    setAttribute: function (к, з) { атрибуты[к] = String(з); },
    getAttribute: function (к) { return (к in атрибуты) ? атрибуты[к] : null; },
    addEventListener: function (тип, fn) { (слушатели[тип] = слушатели[тип] || []).push(fn); },
    // Как в браузере: у выключенной кнопки нажатие не срабатывает.
    click: function () { if (эл.disabled) return; (слушатели.click || []).forEach(function (fn) { fn({}); }); },
    // Нажатие в обход замка «disabled»: проверяет, что модуль сам не пускает второй запрос.
    нажатьМимоЗамка: function () { (слушатели.click || []).forEach(function (fn) { fn({}); }); },
    appendChild: function (реб) { return эл.insertBefore(реб, null); },
    insertBefore: function (реб, опорный) {
      if (реб.parentNode) {
        const старые = реб.parentNode.children;
        старые.splice(старые.indexOf(реб), 1);
      }
      const и = опорный ? эл.children.indexOf(опорный) : -1;
      if (и === -1) эл.children.push(реб); else эл.children.splice(и, 0, реб);
      реб.parentNode = эл;
      return реб;
    },
    contains: function (у) {
      for (let т = у; т; т = т.parentNode) if (т === эл) return true;
      return false;
    },
    querySelector: function (sel) { return найтиПоКлассу(эл, sel.replace(/^\./, '').split(':')[0]); },
    focus: function () {}
  };
  Object.defineProperty(эл, 'id', {
    get: function () { return _id; },
    set: function (з) { _id = з; реестр.set(з, эл); }
  });
  Object.defineProperty(эл, 'textContent', {
    get: function () { return свойТекст + эл.children.map(function (р) { return р.textContent; }).join(''); },
    set: function (з) { эл.записейТекста++; эл.children.length = 0; свойТекст = String(з); }
  });
  // Ловушка: слова надо класть через textContent; innerHTML разбирает теги.
  Object.defineProperty(эл, 'innerHTML', {
    get: function () { return свойТекст; },
    set: function (з) {
      журнал.innerHTML++;
      эл.children.length = 0;
      свойТекст = String(з).replace(/<[^>]*>/g, '');
    }
  });
  return эл;
}

function найтиПоКлассу(корень, класс) {
  for (let i = 0; i < корень.children.length; i++) {
    const р = корень.children[i];
    if (р.classList.contains(класс)) return р;
    const в = найтиПоКлассу(р, класс);
    if (в) return в;
  }
  return null;
}

function создатьDocument(журнал) {
  const реестр = new Map();
  const body = создатьЭлемент('body', реестр, журнал);
  return {
    body: body,
    createElement: function (тег) { return создатьЭлемент(тег, реестр, журнал); },
    getElementById: function (id) { return реестр.get(id) || null; },
    addEventListener: function () {}
  };
}

/** Загрузить модуль в песочницу с поддельной страницей. */
function загрузить(document) {
  const исходник = fs.readFileSync(путьКФайлу, 'utf8');
  const модуль = { exports: {} };
  const песочница = { module: модуль, exports: модуль.exports, console: console,
    setTimeout: setTimeout, clearTimeout: clearTimeout, setInterval: function () { return 0; }, clearInterval: function () {} };
  if (document) песочница.document = document;
  vm.createContext(песочница);
  vm.runInContext(исходник, песочница, { filename: путьКФайлу + ' (в памяти)' });
  return модуль.exports;
}

function собрать() {
  const журнал = { innerHTML: 0 };
  const document = создатьDocument(журнал);
  const Лист = загрузить(document);
  return {
    журнал: журнал, document: document, Лист: Лист,
    плашка: function () { return document.getElementById('плашка-досрочно'); },
    часть: function (класс) { const п = document.getElementById('плашка-досрочно'); return п && п.querySelector('.' + класс); }
  };
}

