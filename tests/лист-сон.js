function словаСна(о) { return Object.assign({}, СЛОВА, о || {}); }

/** Двери сна, отвечающие по команде проверки. Ответы копятся по порядку нажатий. */
function дверьСна() {
  const д = { вызовы: 0, ждущие: [], режим: 'ждать' };
  д.проснуться = function () {
    д.вызовы++;
    if (д.режим === 'бросить') throw new Error('дверь упала сразу');
    return new Promise(function (принять, отклонить) { д.ждущие.push({ принять: принять, отклонить: отклонить }); });
  };
  д.ответить = function (о, н) { д.ждущие[н === undefined ? д.ждущие.length - 1 : н].принять(о); };
  д.упасть = function (н) { д.ждущие[н === undefined ? д.ждущие.length - 1 : н].отклонить(new Error('сеть оборвалась')); };
  return д;
}

/** Двери голосования (только то, что нужно проверке соседства). */
function дверьГолоса() {
  const д = { вызовы: [] };
  д.предложить = function () { д.вызовы.push('предложить'); return new Promise(function () {}); };
  д.голос = function (за) { д.вызовы.push('голос(' + за + ')'); return new Promise(function () {}); };
  return д;
}

