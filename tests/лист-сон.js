const тик = function () { return new Promise(function (r) { setImmediate(r); }); };
// Виден, если не спрятан ни сам узел, ни один из его родителей (как в настоящем CSS).
const видим = function (у) {
  if (!у) return false;
  for (let т = у; т && т.classList; т = т.parentNode) if (т.classList.contains('скрыт')) return false;
  return true;
};

