'use strict';

/* Проверка без браузера: лобби и итог партии домино сделаны как у дурака
   (владелец 02.10: «все онлайн игры в одном стиле, эталон — дурак»).
   Читает разметку и код как текст.

   Запуск:  node tests/домино-как-дурак.js [домино.html] [домино-экран.js] [style-домино.css]
   Пути нужны для «красного» запуска: проверка на КОПИЯХ, где поломку вернули
   (старая верхняя строка, нет места в рейтинге и т.п.), обязана упасть.
   Настоящие файлы портить нельзя.

   Ноль найденных узлов — провал, а не пропуск. */

const fs = require('fs');
const path = require('path');

const корень = path.join(__dirname, '..');
function путь(номер, обычный) {
  return process.argv[номер] ? path.resolve(process.argv[номер]) : path.join(корень, обычный);
}
const путьHtml = путь(2, 'домино.html');
const html = fs.readFileSync(путьHtml, 'utf8');
const экран = fs.readFileSync(путь(3, 'js/домино-экран.js'), 'utf8');
const стили = fs.readFileSync(путь(4, 'style-домино.css'), 'utf8');

let провалов = 0;
let всего = 0;
function проверить(условие, слова) {
  всего++;
  if (!условие) провалов++;
  console.log((условие ? '  ок      ' : '  ПРОВАЛ  ') + слова);
}

/** Кусок текста от начала до конца (включительно); пусто, если не нашли. */
function кусок(текст, начало, конец) {
  const от = текст.indexOf(начало);
  if (от === -1) return '';
  const до = текст.indexOf(конец, от);
  return до === -1 ? '' : текст.slice(от, до + конец.length);
}

console.log('Страница: ' + путьHtml);

const лобби = кусок(html, '<section id="экран-лобби"', '</section>');
console.log('\n1. Верхняя строка лобби');
проверить(лобби.length > 0, 'секция «экран-лобби» найдена');
const верх = кусок(лобби, '<div class="верх-игры">', '</div>');
проверить(верх.length > 0, 'в лобби есть строка «верх-игры» («‹ ⋯» иконками, как у дурака)');
проверить(/data-назад/.test(верх) && /data-меню/.test(верх), 'в строке обе кнопки: «назад» и «меню» (привязки домино-экран.js)');
проверить(/aria-controls="лист-игры"/.test(верх), 'кнопка «⋯» открывает общий лист «лист-игры»');
проверить(!/дом-верх/.test(лобби), 'старой текстовой строки «дом-верх» в лобби нет');
проверить(!/Игры с друзьями/.test(лобби), 'надписи «Игры с друзьями» в лобби нет');

console.log('\n2. Карточка профиля');
const профиль = кусок(лобби, '<button id="лобби-профиль"', '</button>');
проверить(профиль.length > 0, 'карточка «лобби-профиль» найдена');
проверить(/id="лобби-имя"/.test(профиль), 'имя «лобби-имя» на месте (его пишет js/лобби-настольных.js)');
проверить(/id="лобби-рейтинг"[^>]*карточка-профиля__рейтинг--нет/.test(профиль), 'строка «лобби-рейтинг» с классом --нет (пока места нет)');
проверить(/id="лобби-место"/.test(профиль), 'в карточке есть узел «лобби-место»');
проверить(!/Мой профиль и результаты/.test(профиль), 'вечной подписи «Мой профиль и результаты» нет');
проверить(!/серия/i.test(профиль), 'серии побед в карточке нет');
проверить(/ЭкранРейтинга\.моёМесто\('домино'\)/.test(экран), 'место берётся как у дурака: ЭкранРейтинга.моёМесто(\'домино\')');
проверить(/карточка-профиля__рейтинг--нет/.test(экран), 'код ставит/снимает класс --нет по наличию места');
проверить(/getElementById|\$\('лобби-место'\)/.test(экран) && /освежитьМесто\(\)/.test(экран.replace(/function освежитьМесто\(\)/, '')), 'освежитьМесто() где-то вызывается (при показе лобби)');
проверить(/if \(id === 'экран-лобби'\) освежитьМесто\(\)/.test(экран), 'место обновляется при каждом показе лобби');

console.log('\n3. Плашка «доиграть» и картинка');
const плашка = кусок(лобби, '<button id="дом-продолжить"', '</button>');
проверить(плашка.length > 0, 'плашка «дом-продолжить» найдена');
проверить(/class="плашка-возврата[ "]/.test(плашка), 'плашка — общий класс «плашка-возврата», как у дурака');
const картинка = кусок(лобби, '<figure id="дом-афиша"', '</figure>');
проверить(картинка.length > 0, 'картинка-афиша найдена');
проверить(/<figcaption>[^<]*[А-Яа-я]/.test(картинка), 'у картинки есть подпись figcaption');
проверить(/body\.домино\s+\.фото-лобби__обложка\s*\{[^}]*aspect-ratio:\s*16\s*\/\s*10/.test(стили), 'рамка картинки 16:10 задана в style-домино.css');

console.log('\n4. Карточки входов');
проверить(/карточка-входа__название">Играть онлайн</.test(кусок(лобби, '<button id="лобби-найти-игру"', '</button>')), 'карточка «Играть онлайн»');
проверить(/карточка-входа__название">Играть с ботами</.test(кусок(лобби, '<button id="дом-боты"', '</button>')), 'карточка «Играть с ботами»');
проверить(/карточка-входа__название">Как играть</.test(кусок(лобби, '<button id="лобби-правила"', '</button>')), 'карточка «Как играть» до партии');
проверить(/<nav class="нижние-вкладки"/.test(лобби), 'место под нижнюю полосу «Игры · Рейтинг · Профиль»');

console.log('\n5. Лист «⋯»');
const лист = кусок(html, '<div id="лист-игры"', '</div>\n  </div>');
проверить(лист.length > 0, 'лист «лист-игры» найден');
const порядок = ['В меню', 'Как играть', 'Звук', 'Рекорды'].map(с => лист.indexOf('>' + с));
проверить(порядок.every(н => н !== -1) && порядок.every((н, и) => и === 0 || н > порядок[и - 1]), 'строки листа: В меню · Как играть · Звук · Рекорды — в порядке сборника');
проверить(!/Мои результаты/.test(лист), 'строки «Мои результаты» нет (называется «Рекорды»)');

console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
process.exit(провалов === 0 ? 0 : 1);
