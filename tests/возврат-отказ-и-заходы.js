function проверить(условие, что) {
  проверок++;
  if (!условие) { провалы.push(что); console.log('  ПРОВАЛ: ' + что); }
  else console.log('  ок   ' + что);
}

/** Свежая загрузка не-звать.js: модуль забывает всё в памяти и читает файл заново. */
function свежийНеЗвать() {
  delete require.cache[require.resolve(ПУТЬ_НЕ_ЗВАТЬ)];
  const н = require(ПУТЬ_НЕ_ЗВАТЬ);
  н.включитьЗапись();
  return н;
}

function проверитьНеЗвать() {
  console.log('1. Память отказов: «без возврата»');
  const А = 9600101;
  const Б = 9600102;
  const В = 9600103;
  let н = свежийНеЗвать();

  проверить(typeof н.отказатьсяОтВозврата === 'function' && typeof н.отказалсяОтВозврата === 'function',
    '1: есть отказатьсяОтВозврата и отказалсяОтВозврата');
  проверить(н.отказалсяОтВозврата(А) === false, '1: до отказа отказалсяОтВозврата = false');
  проверить(н.отказатьсяОтВозврата(А) === true, '1: отказ принят (true)');
  проверить(н.отказалсяОтВозврата(А) === true, '1: после отказа отказалсяОтВозврата = true');
  проверить(н.отказатьсяОтВозврата('мусор') === false && н.отказатьсяОтВозврата(-5) === false,
    '1: негодный номер не принимается');
  проверить(н.почемуНеЗвать(А) === '', '1: отказ от возврата не делает почемуНеЗвать непустым («' + н.почемуНеЗвать(А) + '»)');
  проверить(н.отказалсяОтИтогов(А) === false, '1: отказ от возврата не трогает отказалсяОтИтогов');
  проверить(н.отказалсяОтВозврата(Б) === false, '1: у другого человека отказа нет (память не «всё да»)');

  // Обратное: отказ от итогов и «сам» не создают отказ от возврата.
  н.отказатьсяОтИтогов(Б);
  н.запретить(В, н.ПРИЧИНЫ.сам);
  проверить(н.отказалсяОтВозврата(Б) === false, '1: отказ от итогов не создаёт отказ от возврата');
  проверить(н.отказалсяОтВозврата(В) === false, '1: «сам» не создаёт отказ от возврата');

  // Перезагрузка модуля: файл читается заново.
  проверить(fs.existsSync(н.ФАЙЛ) && н.ФАЙЛ.indexOf(ПАПКА_ДАННЫХ) === 0, '1: файл памяти лежит во временной папке и записан сразу');
  const н2 = свежийНеЗвать();
  проверить(н2 !== н, '1: модуль загружен заново (другой экземпляр)');
  проверить(н2.отказалсяОтВозврата(А) === true, '1: после перезагрузки отказ от возврата на месте');
  проверить(н2.почемуНеЗвать(А) === '' && н2.отказалсяОтИтогов(А) === false, '1: …и ничего чужого не прибавилось');
  проверить(н2.отказалсяОтИтогов(Б) === true && н2.отказалсяОтВозврата(Б) === false, '1: у Б после перезагрузки только отказ от итогов');
  проверить(н2.почемуНеЗвать(В) === н2.ПРИЧИНЫ.сам && н2.отказалсяОтВозврата(В) === false, '1: у В после перезагрузки только «сам»');

  // Старый файл без списка безВозврата.
  fs.writeFileSync(н2.ФАЙЛ, JSON.stringify({
    запреты: [{ номер: В, причина: 'сам', когда: Date.now() }],
    безИтогов: [{ номер: Б, когда: Date.now() }]
  }), 'utf8');
  let старый = null;
  let упало = '';
  try { старый = свежийНеЗвать(); старый.отказалсяОтВозврата(А); } catch (сбой) { упало = String(сбой && сбой.message); }
  проверить(упало === '' && Boolean(старый), '1: старый файл без безВозврата читается без падения ' + упало);
  проверить(Boolean(старый) && старый.отказалсяОтВозврата(А) === false && старый.отказалсяОтВозврата(Б) === false,
    '1: в старом файле отказов от возврата нет');
  проверить(Boolean(старый) && старый.отказалсяОтИтогов(Б) === true && старый.почемуНеЗвать(В) === 'сам',
    '1: остальное из старого файла прочиталось (итоги Б, «сам» В)');
  if (старый) {
    старый.отказатьсяОтВозврата(А);
    const после = JSON.parse(fs.readFileSync(старый.ФАЙЛ, 'utf8'));
    проверить(Array.isArray(после.безВозврата) && после.безВозврата.length === 1 && после.безВозврата[0].номер === А,
      '1: на диске отказ лежит в своём списке безВозврата');
    проверить(Array.isArray(после.безИтогов) && после.безИтогов.length === 1 && после.безИтогов[0].номер === Б,
      '1: …а в списке безИтогов остался только Б');

    // забытьВсё чистит и эту память.
    старый.забытьВсё();
    проверить(старый.отказалсяОтВозврата(А) === false && старый.отказалсяОтИтогов(Б) === false && старый.почемуНеЗвать(В) === '',
      '1: забытьВсё очистило и отказ от возврата, и остальные');
  }
}

function проверитьЗаходы() {
  console.log('2. Последний заход');
  delete require.cache[require.resolve(ПУТЬ_ПОСЕЩЕНИЙ)];
  const посещения = require(ПУТЬ_ПОСЕЩЕНИЙ);
  проверить(посещения.ИГРЫ.length > 0, '2: опора — в реестре есть игры (' + посещения.ИГРЫ.length + ')');
  const игра = посещения.ИГРЫ[0];
  const уч = посещения.создать({ файл: 'без диска' });
  const МИНУТА = 60 * 1000;
  const ДЕНЬ = 24 * 60 * МИНУТА;
  const день1 = new Date(2026, 8, 20, 12, 0, 0).getTime();
  const день3 = день1 + 2 * ДЕНЬ;
  const день5 = день1 + 4 * ДЕНЬ;
  const сейчас = день5 + 5 * МИНУТА;

  проверить(уч.учесть('9600201', 'Аня', игра, день1) === true, '2: пульс 1-го дня принят');
  проверить(уч.учесть('9600201', 'Аня', игра, день3) === true, '2: пульс 3-го дня принят');
  проверить(уч.учесть('9600201', 'Аня', игра, день5) === true, '2: пульс 5-го дня принят');
  проверить(уч.учесть('9600202', 'Боря', игра, день3) === true, '2: у Бори один пульс на 3-й день');
  проверить(уч.учестьГостя('gost0123456789abcd', игра, день5) === true, '2: пульс гостя принят (опора: гость в учёте есть)');

  const список = уч.последниеЗаходы(сейчас);
  проверить(Array.isArray(список) && список.length >= 1, '2: список не пуст (' + (Array.isArray(список) ? список.length : 'не список') + ')');
  const аня = Array.isArray(список) ? список.find(function (з) { return з.номер === '9600201'; }) : null;
  const боря = Array.isArray(список) ? список.find(function (з) { return з.номер === '9600202'; }) : null;
  проверить(Boolean(аня) && аня.последнийРаз === день5 + МИНУТА,
    '2: у Ани последнийРаз = последний пульс + 1 мин (' + (аня ? аня.последнийРаз - день5 : 'нет записи') + ' мс после пульса, ждали ' + МИНУТА + ')');
  проверить(Boolean(боря) && боря.последнийРаз === день3 + МИНУТА, '2: у Бори последнийРаз = его пульс + 1 мин');
  проверить(Array.isArray(список) && список.length === 2, '2: в списке ровно двое людей, гостя нет (' + (Array.isArray(список) ? список.length : '—') + ')');
  проверить(Array.isArray(список) && !список.some(function (з) { return String(з.номер).indexOf('gost') === 0; }), '2: ид гостя в списке не встречается');
  проверить(Array.isArray(список) && список.every(function (з) { return typeof з.номер === 'string' && /^\d+$/.test(з.номер) && Number.isFinite(з.последнийРаз); }),
    '2: у каждой записи цифровой номер и число последнийРаз');
}

try {
  проверитьНеЗвать();
  проверитьЗаходы();
} catch (беда) {
  проверить(false, 'СБОЙ ПРОВЕРКИ: ' + (беда && беда.stack || беда));
}

try { fs.rmSync(ПАПКА_ДАННЫХ, { recursive: true, force: true }); } catch (с) { /* не беда */ }
