/* =====================================================================
   Этап Э1 плана штаб/план-возврат-ушедших.md: «Отказ от возврата» и
   «последний заход».

   Сверяем:
     1. server/не-звать.js: отказ «без возврата» — отдельная память.
        Он не делает почемуНеЗвать непустым и не трогает отказ от итогов
        (и наоборот); переживает перезагрузку модуля (файл читается
        заново); старый файл без списка безВозврата читается;
        забытьВсё чистит и его.
     2. server/посещения.js: последниеЗаходы(сейчасМс) — три пульса в
        разные дни дают последнийРаз = последний пульс + 1 мин;
        гость в список не попадает; пусто — это провал (ноль найденного).

   Данные — во временной папке (ДАННЫЕ_ИГРЫ), боевые не трогаются.
   Браузер не нужен.

   Запуск:
       node tests/возврат-отказ-и-заходы.js
       node tests/возврат-отказ-и-заходы.js --корень <путь>   (проверяемые
           модули берём из другой папки с server/ и js/ — например, из копии)
   Ломающие прогоны (каждый обязан покраснеть). Проверка сама собирает
   КОПИЮ server/ и js/ во временной папке, портит в ней одно место:
       --сломать-итоги     отказатьсяОтВозврата пишет в безИтогов
       --сломать-начало    последниеЗаходы берёт начало вместо конца
       --сломать-гостей    гости попадают в список последниеЗаходы

   Выход 0 — провалов нет, 1 — есть, 2 — ломающий прогон не состоялся.
   ===================================================================== */

