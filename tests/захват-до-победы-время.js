'use strict';
/* =====================================================================
   ПРОВЕРКА «Захвата», этап ДП1: правила режима «До победы» по часам.
   Предел партии — 10 минут игры (потраченоМс), страховка — 100 раундов.

   Что требуется:
     - у новой партии «До победы»: доПобеды, потраченоМс 0, страховка 100 раундов;
       у обычной партии поля потраченоМс нет и часов (мсДоКонцаПартии) нет — null;
     - разбор раундов по 30 с: партия кончается на 20-м разборе, причина «время»,
       слова «По очкам: 10 минут прошло, полной победы нет», после конца осталось 0;
     - без часов (потраченоМс не растёт) партия кончается на 100-м раунде, причина «раунды»;
     - полная победа (все столицы) на 10:00 — причина «столицы», не «время».

   Запуск:
     node tests/захват-до-победы-время.js                    — проверка
     node tests/захват-до-победы-время.js --файл путь.js     — правила из другого файла (копия)
     node tests/захват-до-победы-время.js --сломать          — ломающие запуски на копиях во
         временной папке: каждая порча правил обязана покраснеть.
   Выход: 0 — зелено; 1 — есть провалы; 2 — порча не покраснела; 3 — порче не нашлось места.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const КОРЕНЬ = path.resolve(__dirname, '..');
const ФАЙЛ_ПРАВИЛ = path.join(КОРЕНЬ, 'js', 'захват-правила.js');
const аргументы = process.argv.slice(2);
const номерФайла = аргументы.indexOf('--файл');

/* ---------- ломающие запуски ---------- */
const ПОРЧИ = [
  { имя: 'часы не кончают партию (срок бесконечен)', найти: 'времяДоПобедыМс: 600000', на: 'времяДоПобедыМс: Infinity' },
  { имя: 'время не проверяется после раунда', найти: "if (послеРаунда && времяВышло(партия)) return { причина: 'время', победитель: null };", на: '' },
  { имя: 'новая партия не обнуляет потраченоМс', найти: 'if (партия.доПобеды) партия.потраченоМс = 0;', на: '' },
  { имя: 'страховки по раундам нет', найти: 'страховкаДоПобеды: 100', на: 'страховкаДоПобеды: 1000000' },
  { имя: 'у обычной партии появились часы', найти: 'if (!партия.доПобеды) return null;\n    return Math.max(0, ЧИСЛА.раундов.времяДоПобедыМс', на: 'if (false) return null;\n    return Math.max(0, ЧИСЛА.раундов.времяДоПобедыМс' },
  { имя: 'слова причины «время» не те', найти: "' прошло, полной победы нет'", на: "' прошло'" }
];

function сломать() {
  const исходник = fs.readFileSync(ФАЙЛ_ПРАВИЛ, 'utf8');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-время-'));
  let худшее = 0;
  ПОРЧИ.forEach((п, н) => {
    const мест = исходник.split(п.найти).length - 1;
    if (мест !== 1) { console.log('  ПЛОХО — порча «' + п.имя + '»: образец найден ' + мест + ' раз, нужен ровно 1'); худшее = Math.max(худшее, 3); return; }
    const копия = path.join(папка, 'правила-' + н + '.js');
    // Правила подтягивают карты по соседнему пути — в копии даём абсолютный.
    const карты = JSON.stringify(path.join(КОРЕНЬ, 'js', 'захват-карты.js'));
    fs.writeFileSync(копия, исходник.replace(п.найти, () => п.на).replace("require('./захват-карты.js')", () => 'require(' + карты + ')'));
    const итог = spawnSync(process.execPath, [__filename, '--файл', копия], { encoding: 'utf8' });
    const красное = итог.status === 1;
    console.log((красное ? '  ок    — покраснело: ' : '  ПЛОХО — НЕ ПОКРАСНЕЛО: ') + п.имя + ' (код ' + итог.status + ')');
    if (!красное) худшее = Math.max(худшее, 2);
  });
  console.log('Копии лежат в ' + папка + ' (проект не тронут)');
  process.exit(худшее);
}
if (аргументы.includes('--сломать')) сломать();

/* ---------- сама проверка ---------- */
const П = require(номерФайла >= 0 ? path.resolve(аргументы[номерФайла + 1]) : ФАЙЛ_ПРАВИЛ);
let провалов = 0;
let всего = 0;
function ждём(имя, ок) { всего++; if (!ок) { провалов++; console.log('ПРОВАЛ: ' + имя); } }
function партия(победа) {
  return П.новаяПартия({ игроки: ['a', 'b', 'c', 'd', 'e', 'f'], люди: [], сейчас: 0, раундовЗахвата: победа ? 'победа' : 15 }, () => 0.5);
}

let п = партия(true);
ждём('поля новой партии (ноль — провал)', п.доПобеды === true && п.потраченоМс === 0 && п.всегоРаундов === 100);
ждём('у обычной нет потраченоМс и часов', !('потраченоМс' in партия(false)) && П.мсДоКонцаПартии(партия(false)) === null);
ждём('в начале осталось 10 минут', П.мсДоКонцаПартии(п) === 600000);

// Разбор по 30 с: конец на 20-м разборе по времени.
let раз = 0;
while (!п.завершена && раз < 200) { п.потраченоМс += 30000; раз++; п = П.разобратьРаунд(п, {}, () => 0.5).партия || п; }
ждём('разбор переносит потраченоМс', п.потраченоМс === раз * 30000);
ждём('конец на 20-м разборе по времени', раз === 20 && !!п.итог && п.итог.причина === 'время');
ждём('слова причины', !!п.итог && П.итог(п).итог.словами === 'По очкам: 10 минут прошло, полной победы нет');
ждём('после конца осталось 0', П.мсДоКонцаПартии(п) === 0);

// Без часов — страховка 100 раундов.
let q = партия(true);
let н = 0;
while (!q.завершена && н < 200) { н++; q = П.разобратьРаунд(q, {}, () => 0.5).партия || q; }
ждём('страховка: конец на 100-м раунде, причина «раунды»', н === 100 && !!q.итог && q.итог.причина === 'раунды');

// Полная победа на 10:00 — «столицы», не «время».
const г = партия(true);
г.потраченоМс = 600000;
г.раунд = 5;
ждём('столицы у партии есть (ноль — провал)', Array.isArray(г.столицы) && г.столицы.length > 0);
г.столицы.forEach(с => { г.хозяева[с.область] = 'a'; });
const р = П.разобратьРаунд(г, {}, () => 0.5);
const итог = (р.партия || р).итог;
ждём('столицы раньше времени', !!итог && итог.причина === 'столицы');

console.log('Итого проверок: ' + всего + ', провалов: ' + провалов);
process.exit(провалов ? 1 : 0);
