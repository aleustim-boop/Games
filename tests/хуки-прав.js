/*
  Проверка трёх хуков прав исполнителей:
    .claude/hooks/начало-исполнителя.js     (PostToolUse, matcher "Agent")
    .claude/hooks/охрана-файлов.js          (PreToolUse, matcher "Edit|Write|MultiEdit")
    .claude/hooks/по-окончании-исполнителя.js (SubagentStop)

  ГЛАВНОЕ ОГРАНИЧЕНИЕ: боевые хуки и штаб/права.json, штаб/в-работе.json,
  штаб/охрана-журнал.txt не трогаем — под ними прямо сейчас работают другие
  исполнители. Вся проверка идёт в своей временной папке
  (os.tmpdir()/хуки-прав-<время>/), куда копируются ТЕКСТЫ трёх хуков и
  заводятся свои штаб/права.json, штаб/в-работе.json, штаб/в-работе.js
  (заглушка) и файлы-цели (tests/а.js, js/б.js, style.css, server.js).
  Хуки сами вычисляют корень как path.join(__dirname, '..', '..') — в копии
  это и будет временная папка, боевые файлы физически недостижимы.

  Два прогона:
    node tests/хуки-прав.js            — обычный, ждём «провалов: 0».
    node tests/хуки-прав.js --сломать  — портит СВОИ копии хуков:
      в охране ВСЕ блокирующие «process.exit(2);» меняются на пропуск
      (их теперь два: чужой файл и пустой список файлов),
      в по-окончании пометка «завершил» меняется на удаление записи.
      Ждём M > 0 провалов ровно там, где это и должно сломаться.

  Сценарии (нумерация из задания):
    1. Старт исполнителя с «Файлы: tests/а.js, js/б.js» → запись в правах.
    2. Охрана: Edit на свой файл — пропуск; Edit на style.css — блокировка;
       «Read» на style.css — пропуск (Read не в списке пишущих инструментов).
    3. Дыра «Bash не проверяется» (закрыта 23.09): перенаправление «>»/«>>»,
       sed -i, tee, cp/mv, PowerShell Set-Content/Out-File — цель вне прав
       блокируется, цель в правах или во временной папке — пропускается.
    4. Стоп исполнителя → запись помечена «завершил», не удалена; охрана
       всё ещё пропускает возвращённого исполнителя тем же номером.
    5. Чистка записей «завершил» старше 24 часов при чужом SubagentStop.
    6. Дыра «пустые файлы = можно всё» (закрыта 23.09): у НАЙДЕННОЙ записи
       исполнителя пустой список файлов теперь блокирует правку файлов
       проекта, кроме временных путей.
    7. Исполнитель, для которого в правах вообще НЕТ записи (ни по номеру,
       ни по роли) — работает как раньше: пропуск с предупреждением. Это
       не тот же случай, что №6, и правка не должна была его затронуть.
*/
