fs.writeFileSync(path.join(ВРЕМ, 'js', 'б.js'), '// пусто\n', 'utf8');
fs.writeFileSync(path.join(ВРЕМ, 'style.css'), '/* пусто */\n', 'utf8');
fs.writeFileSync(path.join(ВРЕМ, 'server.js'), '// файл, которого нет ни в чьём задании\n', 'utf8');

function запуск(путь, событие) {
  const рез = spawnSync(process.execPath, [путь], {
    input: JSON.stringify(событие),
    encoding: 'utf8',
    timeout: 15000,
  });
  return рез;
}
function читатьПрава() {
  return JSON.parse(fs.readFileSync(ФАЙЛ_ПРАВ, 'utf8'));
}
function читатьРаботы() {
  return JSON.parse(fs.readFileSync(ФАЙЛ_РАБОТ, 'utf8'));
}
function читатьЖурналПоследнюю() {
  let строки = [];
  try { строки = fs.readFileSync(ФАЙЛ_ЖУРНАЛА, 'utf8').split('\n').filter(Boolean); } catch (о) { return null; }
  if (строки.length === 0) return null;
  try { return JSON.parse(строки[строки.length - 1]); } catch (о) { return null; }
}
function числоСтрокЖурнала() {
  try { return fs.readFileSync(ФАЙЛ_ЖУРНАЛА, 'utf8').split('\n').filter(Boolean).length; } catch (о) { return 0; }
}

