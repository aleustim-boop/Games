let текстСтопОригинал = fs.readFileSync(path.join(ХУКИ_ИСТОЧНИК, ИМЯ_СТОП), 'utf8');

let сломаноОхрана = false;
let сломаноСтоп = false;

if (СЛОМАТЬ) {
  // Порча копии охраны: в коде теперь ДВА блокирующих «process.exit(2);» —
  // «чужой файл» и «пустой список файлов» (дыра 2). Меняем оба разом через
  // глобальную регулярку, иначе .replace() строкой погасил бы только первый
  // и вторая блокировка осталась бы «случайно рабочей», а мы бы решили, что
  // порча не нужна.
  const метка1 = /process\.exit\(2\);/g;
  const совпаденияОхрана = текстОхранаОригинал.match(метка1);
  if (совпаденияОхрана && совпаденияОхрана.length > 0) {
    текстОхранаОригинал = текстОхранаОригинал.replace(метка1, 'process.exit(0); /* СЛОМАНО ПРОВЕРКОЙ: всегда пропускать */');
    сломаноОхрана = true;
  }

  // Порча копии стопа: пометку «завершил» заменяем на удаление записи.
  const метка2 = 'права[agentIdСырой].завершил = сейчас;';
  if (текстСтопОригинал.includes(метка2)) {
    текстСтопОригинал = текстСтопОригинал.replace(метка2, 'delete права[agentIdСырой]; /* СЛОМАНО ПРОВЕРКОЙ: удаляем вместо пометки */');
    сломаноСтоп = true;
  }

  проверить(
    '0. порча копий хуков применилась (иначе текст хука изменился, и проверку надо обновить)',
    сломаноОхрана && сломаноСтоп,
    'сломаноОхрана=' + сломаноОхрана + ' (найдено process.exit(2): ' + (совпаденияОхрана ? совпаденияОхрана.length : 0) + '), сломаноСтоп=' + сломаноСтоп
  );
}

