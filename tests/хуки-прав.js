// execFileSync в try/catch и молча глотают ошибку, если файла нет вовсе —
// заглушка нужна только чтобы не шуметь в stderr.
fs.writeFileSync(path.join(ВРЕМ, 'штаб', 'в-работе.js'), 'process.exit(0);\n', 'utf8');

