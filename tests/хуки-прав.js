// ---------- Сценарий 1: старт исполнителя ----------
{
  const событие = {
    tool_name: 'Agent',
    tool_input: {
      subagent_type: 'tester',
      description: 'Тестовый исполнитель',
      prompt: 'Почини всплывающую подсказку. Файлы: tests/а.js, js/б.js — только они, другое не трогай.',
    },
    tool_response: 'Async agent launched successfully. agentId: ' + НОМЕР_1,
  };
  const рез = запуск(ПУТЬ_НАЧАЛО, событие);
  проверить('1. старт-хук завершился без ошибки процесса', рез.status === 0, 'status=' + рез.status + ' stderr=' + рез.stderr);

  const права = читатьПрава();
  проверить('1. в правах появилась запись с номером агента', !!права[НОМЕР_1], 'ключей в правах: ' + Object.keys(права).length);
  if (права[НОМЕР_1]) {
    проверить(
      '1. файлы разобраны верно из «Файлы: tests/а.js, js/б.js — только они»',
      JSON.stringify(права[НОМЕР_1].файлы) === JSON.stringify(['tests/а.js', 'js/б.js']),
      'получено: ' + JSON.stringify(права[НОМЕР_1].файлы)
    );
    проверить('1. поле «начал» похоже на дату-время', /^\d{4}-\d{2}-\d{2} \d{2}:\d{2}$/.test(права[НОМЕР_1].начал), права[НОМЕР_1].начал);
  }

  const работы = читатьРаботы();
  проверить(
    '1. в штаб/в-работе.json появилась запись этого агента',
    работы.работы.some((р) => р.задача === НОМЕР_1 && р.кто === 'tester'),
    JSON.stringify(работы.работы)
  );
}

