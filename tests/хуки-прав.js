function проверить(название, условие, детали) {
  проверок++;
  if (!условие) {
    провалы.push(название + (детали ? ' — ' + детали : ''));
    console.log('[ПРОВАЛ] ' + название + (детали ? ' — ' + детали : ''));
  } else {
    console.log('[ок] ' + название);
  }
}

// ---------- времяЗаписью: та же логика, что в хуках, для ручных записей ----------
function времяЗаписью(дата) {
  const дв = (ч) => String(ч).padStart(2, '0');
  return дата.getFullYear() + '-' + дв(дата.getMonth() + 1) + '-' + дв(дата.getDate())
    + ' ' + дв(дата.getHours()) + ':' + дв(дата.getMinutes());
}

