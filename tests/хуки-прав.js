/*
  Проверка трёх хуков прав исполнителей:
    .claude/hooks/начало-исполнителя.js     (PostToolUse, matcher "Agent")
    .claude/hooks/охрана-файлов.js          (PreToolUse, matcher "Edit|Write|MultiEdit")
    .claude/hooks/по-окончании-исполнителя.js (SubagentStop)

  ГЛАВНОЕ ОГРАНИЧЕНИЕ: боевые хуки и штаб/права.json, штаб/в-работе.json,
  штаб/охрана-журнал.txt не трогаем — под ними прямо сейчас работают другие
  исполнители. Вся проверка идёт в своей временной папке
  (os.tmpdir()/хуки-прав-<время>/), куда копируются ТЕКСТЫ трёх хуков и
  заводятся свои штаб/права.json, штаб/в-работе.json, штаб/в-работе.js
  (заглушка) и файлы-цели (tests/а.js, js/б.js, style.css, server.js).
  Хуки сами вычисляют корень как path.join(__dirname, '..', '..') — в копии
  это и будет временная папка, боевые файлы физически недостижимы.

  Два прогона:
    node tests/хуки-прав.js            — обычный, ждём «провалов: 0».
    node tests/хуки-прав.js --сломать  — портит СВОИ копии хуков:
      в охране условие блокировки меняется на «всегда пропускать»,
      в по-окончании пометка «завершил» меняется на удаление записи.
      Ждём M > 0 провалов ровно там, где это и должно сломаться.

  Сценарии (нумерация из задания):
    1. Старт исполнителя с «Файлы: tests/а.js, js/б.js» → запись в правах.
    2. Охрана: Edit на свой файл — пропуск; Edit на style.css — блокировка;
       «Read» на style.css — что реально происходит (см. находку в конце).
    3. Bash с записью в чужой файл — что делает хук по коду (см. находку).
    4. Стоп исполнителя → запись помечена «завершил», не удалена; охрана
       всё ещё пропускает возвращённого исполнителя тем же номером.
    5. Чистка записей «завершил» старше 24 часов при чужом SubagentStop.
    6. Исполнитель без строки «Файлы:» — что делает хук по коду.
*/
'use strict';

const fs = require('fs');
const path = require('path');
const os = require('os');
const { spawnSync } = require('child_process');

const КОРЕНЬ_ПРОЕКТА = path.join(__dirname, '..');
const ХУКИ_ИСТОЧНИК = path.join(КОРЕНЬ_ПРОЕКТА, '.claude', 'hooks');
const НАСТРОЙКИ_ИСТОЧНИК = path.join(КОРЕНЬ_ПРОЕКТА, '.claude', 'settings.json');

const СЛОМАТЬ = process.argv.includes('--сломать');

let проверок = 0;
const провалы = [];

function проверить(название, условие, детали) {
  проверок++;
  if (!условие) {
    провалы.push(название + (детали ? ' — ' + детали : ''));
    console.log('[ПРОВАЛ] ' + название + (детали ? ' — ' + детали : ''));
  } else {
    console.log('[ок] ' + название);
  }
}

// ---------- времяЗаписью: та же логика, что в хуках, для ручных записей ----------
function времяЗаписью(дата) {
  const дв = (ч) => String(ч).padStart(2, '0');
  return дата.getFullYear() + '-' + дв(дата.getMonth() + 1) + '-' + дв(дата.getDate())
    + ' ' + дв(дата.getHours()) + ':' + дв(дата.getMinutes());
}

// ---------- подготовка временной копии ----------
const ВРЕМ = path.join(os.tmpdir(), 'хуки-прав-' + Date.now());
fs.mkdirSync(path.join(ВРЕМ, '.claude', 'hooks'), { recursive: true });
fs.mkdirSync(path.join(ВРЕМ, 'штаб'), { recursive: true });
fs.mkdirSync(path.join(ВРЕМ, 'tests'), { recursive: true });
fs.mkdirSync(path.join(ВРЕМ, 'js'), { recursive: true });

const ИМЯ_НАЧАЛО = 'начало-исполнителя.js';
const ИМЯ_ОХРАНА = 'охрана-файлов.js';
const ИМЯ_СТОП = 'по-окончании-исполнителя.js';

const текстНачалоОригинал = fs.readFileSync(path.join(ХУКИ_ИСТОЧНИК, ИМЯ_НАЧАЛО), 'utf8');
let текстОхранаОригинал = fs.readFileSync(path.join(ХУКИ_ИСТОЧНИК, ИМЯ_ОХРАНА), 'utf8');
let текстСтопОригинал = fs.readFileSync(path.join(ХУКИ_ИСТОЧНИК, ИМЯ_СТОП), 'utf8');

let сломаноОхрана = false;
let сломаноСтоп = false;

if (СЛОМАТЬ) {
  // Порча копии охраны: единственное место блокировки — process.exit(2) —
  // меняем на пропуск. Журнал по-прежнему пишет «запрет» (это вычисляется
  // раньше), а вот реальный код выхода станет 0 — так и должно покраснеть.
  const метка1 = 'process.exit(2);';
  if (текстОхранаОригинал.includes(метка1)) {
    текстОхранаОригинал = текстОхранаОригинал.replace(метка1, 'process.exit(0); /* СЛОМАНО ПРОВЕРКОЙ: всегда пропускать */');
    сломаноОхрана = true;
  }

  // Порча копии стопа: пометку «завершил» заменяем на удаление записи.
  const метка2 = 'права[agentIdСырой].завершил = сейчас;';
  if (текстСтопОригинал.includes(метка2)) {
    текстСтопОригинал = текстСтопОригинал.replace(метка2, 'delete права[agentIdСырой]; /* СЛОМАНО ПРОВЕРКОЙ: удаляем вместо пометки */');
    сломаноСтоп = true;
  }

  проверить(
    '0. порча копий хуков применилась (иначе текст хука изменился, и проверку надо обновить)',
    сломаноОхрана && сломаноСтоп,
    'сломаноОхрана=' + сломаноОхрана + ', сломаноСтоп=' + сломаноСтоп
  );
}

fs.writeFileSync(path.join(ВРЕМ, '.claude', 'hooks', ИМЯ_НАЧАЛО), текстНачалоОригинал, 'utf8');
fs.writeFileSync(path.join(ВРЕМ, '.claude', 'hooks', ИМЯ_ОХРАНА), текстОхранаОригинал, 'utf8');
fs.writeFileSync(path.join(ВРЕМ, '.claude', 'hooks', ИМЯ_СТОП), текстСтопОригинал, 'utf8');

