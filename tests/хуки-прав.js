// ---------- «Read» на чужой файл: проверяем по коду и по фактическому прогону ----------
{
  // (а) Единственная настоящая защита чтения — matcher в settings.json:
  // PreToolUse для охраны навешан только на "Edit|Write|MultiEdit". Проверяем
  // боевой (не временный — это статичный файл настроек, не трогаем и не
  // портим) settings.json.
  const настройки = JSON.parse(fs.readFileSync(НАСТРОЙКИ_ИСТОЧНИК, 'utf8'));
  const преТулШаги = (настройки.hooks && настройки.hooks.PreToolUse) || [];
  const шагОхраны = преТулШаги.find((ш) => (ш.hooks || []).some((х) => String(х.command || '').includes('охрана-файлов.js')));
  проверить('2. в settings.json нашёлся шаг PreToolUse для охраны', !!шагОхраны, JSON.stringify(преТулШаги));
  if (шагОхраны) {
    проверить(
      '2. matcher охраны — ровно «Edit|Write|MultiEdit» (Read туда не долетает)',
      шагОхраны.matcher === 'Edit|Write|MultiEdit',
      'matcher=' + шагОхраны.matcher
    );
  }

  // (б) НАХОДКА: сам файл хука tool_name вообще не смотрит (только
  // tool_input.file_path и agent_type/agent_id). Значит если matcher
  // когда-нибудь расширят и добавят туда Read, хук так же заблокирует
  // чтение чужого файла, как блокирует запись — защита «чтение не
  // блокируют» держится ИСКЛЮЧИТЕЛЬНО на settings.json, не на коде хука.
  проверить('2. по коду хук нигде не смотрит на tool_name (структурная проверка)', !текстОхранаОригинал.includes('tool_name'), 'слово tool_name найдено в тексте хука');

  const событиеRead = {
    tool_name: 'Read',
    tool_input: { file_path: path.join(ВРЕМ, 'style.css') },
    agent_id: НОМЕР_1,
    agent_type: 'tester',
  };
  const резRead = запуск(ПУТЬ_ОХРАНА, событиеRead);
  проверить(
    '2. НАХОДКА подтверждена прогоном: событие с tool_name="Read" и чужим file_path хук блокирует так же, как Edit (код 2) — потому что tool_name не проверяется',
    резRead.status === 2,
    'status=' + резRead.status + '; это ожидаемо ПРИ ТЕКУЩЕМ КОДЕ, но означает, что защита чтения — целиком на matcher в settings.json, а не в самом хуке'
  );
}

// ---------- Сценарий 3: Bash с записью в чужой файл ----------
{
  const строкДоЖурнала = числоСтрокЖурнала();
  const событиеBash = {
    tool_name: 'Bash',
    tool_input: { command: 'echo подмена > style.css' },
    agent_id: НОМЕР_1,
    agent_type: 'tester',
  };
  const резBash = запуск(ПУТЬ_ОХРАНА, событиеBash);
  // По коду: file_path берётся только из tool_input.file_path или
  // tool_input.edits[0].file_path. У Bash есть только tool_input.command —
  // значит файлПравки остаётся пустым, и хук выходит по ветке
  // «if (!файлПравки) process.exit(0);» ДО обращения к правам.json —
  // никакой проверки содержимого команды не происходит вовсе.
  проверить(
    '3. НАХОДКА подтверждена: Bash-команда «echo … > style.css» пропущена без проверки (код 0) — хук не разбирает tool_input.command, значит sed/echo-перезапись чужого файла из Bash охрана-файлов.js не ловит',
    резBash.status === 0,
    'status=' + резBash.status
  );
  const строкПослеЖурнала = числоСтрокЖурнала();
  проверить('3. Bash-случай даже не попал в журнал (файлПравки пуст — до записи в журнал дело не доходит)', строкПослеЖурнала === строкДоЖурнала, 'было ' + строкДоЖурнала + ', стало ' + строкПослеЖурнала);
}

// ---------- Сценарий 4: стоп исполнителя, «завершил» без удаления, возвращённый ----------
{
  const событиеСтоп = { agent_type: 'tester', status: 'completed', agent_id: НОМЕР_1 };
  const резСтоп = запуск(ПУТЬ_СТОП, событиеСтоп);
  проверить('4. стоп-хук завершился без ошибки процесса', резСтоп.status === 0, 'status=' + резСтоп.status + ' stderr=' + резСтоп.stderr);

  const права = читатьПрава();
  проверить('4. запись исполнителя НЕ удалена из прав.json после стопа', !!права[НОМЕР_1], 'ключей осталось: ' + Object.keys(права).length);
  if (права[НОМЕР_1]) {
    проверить('4. запись помечена полем «завершил»', !!права[НОМЕР_1].завершил, JSON.stringify(права[НОМЕР_1]));
  }

  const работы = читатьРаботы();
  проверить('4. запись снята из штаб/в-работе.json (агент больше не «в работе»)', !работы.работы.some((р) => р.задача === НОМЕР_1), JSON.stringify(работы.работы));

  // Возвращённый исполнитель — тот же номер, штаб зовёт его дальше.
  const событиеПовтор = {
    tool_name: 'Edit',
    tool_input: { file_path: path.join(ВРЕМ, 'tests', 'а.js'), old_string: 'x', new_string: 'z' },
    agent_id: НОМЕР_1,
    agent_type: 'tester',
  };
  const резПовтор = запуск(ПУТЬ_ОХРАНА, событиеПовтор);
  проверить('4. охрана всё ещё пропускает Edit tests/а.js тем же номером после стопа (возвращённый исполнитель)', резПовтор.status === 0, 'status=' + резПовтор.status + ' stderr=' + резПовтор.stderr);

  const журналПовтор = читатьЖурналПоследнюю();
  проверить(
    '4. журнал явно отмечает путь «номер-возвращённый» (не просто «повезло со случайным пропуском»)',
    !!журналПовтор && журналПовтор['чем-нашли'] === 'номер-возвращённый' && журналПовтор.решение === 'пропуск',
    JSON.stringify(журналПовтор)
  );
}

// ---------- Сценарий 5: чистка записей «завершил» старше 24 часов ----------
{
  const права = читатьПрава();
  const времяСтарое = времяЗаписью(new Date(Date.now() - 25 * 60 * 60 * 1000)); // 25 часов назад
  const времяСвежее = времяЗаписью(new Date(Date.now() - 1 * 60 * 60 * 1000)); // 1 час назад
  права[НОМЕР_СТАРЫЙ] = { имя: 'developer', роль: 'developer', файлы: ['index.html'], начал: времяСтарое, номер: НОМЕР_СТАРЫЙ, завершил: времяСтарое };
  права[НОМЕР_СВЕЖИЙ] = { имя: 'developer', роль: 'developer', файлы: ['index.html'], начал: времяСвежее, номер: НОМЕР_СВЕЖИЙ, завершил: времяСвежее };
  fs.writeFileSync(ФАЙЛ_ПРАВ, JSON.stringify(права, null, 2) + '\n', 'utf8');

  // Чистка идёт при КАЖДОМ вызове SubagentStop, даже для совсем другого
  // агента — цикл вычистки в коде стоит вне условия «роль || agentId».
  const событиеЧужогоСтопа = { agent_type: 'reviewer', status: 'completed', agent_id: НОМЕР_ЧИСТКИ };
  запуск(ПУТЬ_СТОП, событиеЧужогоСтопа);

  const праваПослеЧистки = читатьПрава();
  проверить('5. запись старше 24 часов (завершил давно) вычищена', !праваПослеЧистки[НОМЕР_СТАРЫЙ], JSON.stringify(праваПослеЧистки[НОМЕР_СТАРЫЙ]));
  проверить('5. свежая запись (завершил час назад) осталась', !!праваПослеЧистки[НОМЕР_СВЕЖИЙ], 'запись пропала');
}

// ---------- Сценарий 6: исполнитель без строки «Файлы:» ----------
{
  const событие = {
    tool_name: 'Agent',
    tool_input: {
      subagent_type: 'developer',
      description: 'Исполнитель без списка файлов',
      prompt: 'Почини баг в отображении карт на столе.',
    },
    tool_response: 'Async agent launched successfully. agentId: ' + НОМЕР_БЕЗ_ФАЙЛОВ,
  };
  const рез = запуск(ПУТЬ_НАЧАЛО, событие);
  проверить('6. старт-хук без «Файлы:» не падает', рез.status === 0, 'status=' + рез.status + ' stderr=' + рез.stderr);

  const права = читатьПрава();
  проверить('6. запись создана, но со списком файлов []', !!права[НОМЕР_БЕЗ_ФАЙЛОВ] && Array.isArray(права[НОМЕР_БЕЗ_ФАЙЛОВ].файлы) && права[НОМЕР_БЕЗ_ФАЙЛОВ].файлы.length === 0, JSON.stringify(права[НОМЕР_БЕЗ_ФАЙЛОВ]));

  // НАХОДКА: пустой список файлов = ПОЛНЫЙ пропуск без проверки (не
  // «заблокировать всё»), потому что охрана трактует пустой список так же,
  // как «записи вообще нет».
  const событиеЛюбойФайл = {
    tool_name: 'Edit',
    tool_input: { file_path: path.join(ВРЕМ, 'server.js'), old_string: 'x', new_string: 'y' },
    agent_id: НОМЕР_БЕЗ_ФАЙЛОВ,
    agent_type: 'developer',
  };
  const резЛюбойФайл = запуск(ПУТЬ_ОХРАНА, событиеЛюбойФайл);
  проверить(
    '6. НАХОДКА: без строки «Файлы:» исполнитель может править ЛЮБОЙ файл без единой блокировки (код 0)',
    резЛюбойФайл.status === 0,
    'status=' + резЛюбойФайл.status
  );
  const журнал = читатьЖурналПоследнюю();
  проверить('6. журнал отмечает это как «нет-записи» (то же, что и полное отсутствие правил)', !!журнал && журнал['чем-нашли'] === 'нет-записи' && журнал.решение === 'пропуск', JSON.stringify(журнал));
}

