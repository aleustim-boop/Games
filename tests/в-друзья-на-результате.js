'use strict';

/* =====================================================================
   «В ДРУЗЬЯ» И РЕВАНШ НА ЭКРАНЕ РЕЗУЛЬТАТА (этап Э7в плана «Сыграть с другом»)

   На экране результата партии ПО СЕТИ (не против бота) у каждой из 6 игр
   должен появиться пустой узел, в который общее/js/сеть.js сам рисует кнопку
   «В друзья»: игра лишь вызывает window.Сеть.кнопкаВДрузья(узел) один раз
   на показ итога. Проверяется по каждому из 6 файлов:
     1. есть вызов window.Сеть.кнопкаВДрузья(...);
     2. есть отправка действия «ещё» (реванш по сети);
     3. вызов «В друзья» стоит под условием сетевой игры (поСети / online /
        этоСетеваяИгра) — не рисуется в партии с ботом.
   Для игры «дурак» дополнительно поднимаются в vm настоящие функции
   узелВДрузья/освежитьКнопкуВДрузья с поддельными document/window и
   проверяется живое поведение: один вызов на показ итога даже при
   повторном ре-рендере, и полное отсутствие вызова без window.Сеть.

   Ломающий запуск — на КОПИИ одного из файлов во временной папке:
       node tests/в-друзья-на-результате.js --подменить=домино:<путь-к-копии>
   Настоящие файлы проекта при этом не трогаем.
   Код выхода: 0 — всё зелено, 1 — есть провалы.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const КОРЕНЬ = path.resolve(__dirname, '..');

let проверок = 0;
let провалов = 0;
function проверить(условие, слова) {
  проверок++;
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}

function довод(имя) {
  const найдено = process.argv.find(function (с) { return с.indexOf('--' + имя + '=') === 0; });
  return найдено ? найдено.slice(имя.length + 3) : '';
}

// --- список игр и их файлов --------------------------------------------
const ИГРЫ = [
  { имя: 'дурак', файл: path.join(КОРЕНЬ, 'игры', 'дурак', 'game.js') },
  { имя: 'деберц', файл: path.join(КОРЕНЬ, 'игры', 'деберц', 'деберц-экран.js') },
  { имя: 'катан', файл: path.join(КОРЕНЬ, 'игры', 'катан', 'катан-экран.js') },
  { имя: 'домино', файл: path.join(КОРЕНЬ, 'игры', 'домино', 'домино-экран.js') },
  { имя: 'морской-бой', файл: path.join(КОРЕНЬ, 'игры', 'морской-бой', 'морской-бой-экран.js') },
  { имя: 'монополия', файл: path.join(КОРЕНЬ, 'игры', 'монополия', 'монополия-экран.js') },
];

// --- --подменить=имя:путь — для ломающего прогона на копии файла --------
const подмена = довод('подменить');
if (подмена) {
  const делитель = подмена.indexOf(':');
  if (делитель < 0) {
    console.log('Формат довода: --подменить=имя-игры:путь-к-файлу');
    process.exit(1);
  }
  const имя = подмена.slice(0, делитель);
  const путь = подмена.slice(делитель + 1);
  const игра = ИГРЫ.find(function (и) { return и.имя === имя; });
  if (!игра) {
    console.log('Неизвестная игра «' + имя + '». Известные: ' + ИГРЫ.map(function (и) { return и.имя; }).join(', '));
    process.exit(1);
  }
  игра.файл = путь;
  console.log('Ломающий прогон: файл игры «' + имя + '» подменён на ' + путь);
}

// Вызов «В друзья» и вправду под условием сетевой игры, а не рисуется и
// в партии с ботом: ищем рядом с самим вызовом слово поСети/online/
// этоСетеваяИгра, а если вызов лежит внутри отдельной функции-обёртки
// (например «освежитьКнопкуВДрузья») — берём ближайшее объявление функции
// ПЕРЕД вызовом и ищем условие рядом с вызовами уже этой обёртки.
function вызовЗащищёнУсловиемСети(текст) {
  const словоУсловия = /поСети|online|этоСетеваяИгра/;
  /* Охватывающие блоки: идём вверх по строкам от позиции и берём каждую
     строку-открытие блока («… {») с отступом меньше текущего — это и есть
     условия, под которыми стоит вызов, как бы далеко они ни были. Окно в
     символах для этого не годится: после правок деберца (7122e87, 02.10)
     между «if (поСети) {» и вызовом стало 715 знаков, и проверка покраснела
     на исправном коде. Охватывающий «if (поСети)» теперь видно на любой
     дальности. */
  const охватывающиеУсловия = function (позиция) {
    const строки = текст.slice(0, позиция).split('\n');
    const найденные = [];
    let отступ = (строки[строки.length - 1].match(/^\s*/) || [''])[0].length;
    // Последняя строка — часть строки вызова до самого вызова: её отступ и берём.
    for (let н = строки.length - 2; н >= 0 && отступ > 0; н--) {
      const строка = строки[н].replace(/\r$/, '');
      if (!строка.trim()) continue;
      const этотОтступ = строка.search(/\S/);
      if (этотОтступ < отступ && /\{\s*(\/\/.*)?$/.test(строка)) {
        найденные.push(строка);
        отступ = этотОтступ;
      }
    }
    return найденные;
  };
  const стоитПодУсловием = function (позиция) {
    return охватывающиеУсловия(позиция).some(function (строка) { return словоУсловия.test(строка); });
  };
  // Окно намеренно широкое (полтысячи символов) — условие сети часто стоит
  // строкой «if (поСети) {» на несколько строк выше самого вызова.
  const ОКНО = 500;
  const вызовыКнопки = Array.from(текст.matchAll(/Сеть\??\.\s*кнопкаВДрузья/g));
  for (const совп of вызовыКнопки) {
    const окноРядом = текст.slice(Math.max(0, совп.index - ОКНО), совп.index);
    if (словоУсловия.test(окноРядом) || стоитПодУсловием(совп.index)) return true;

    const объявления = Array.from(текст.slice(0, совп.index).matchAll(/function\s+(\S+)\s*\(/g));
    if (объявления.length === 0) continue;
    const имяОбёртки = объявления[объявления.length - 1][1].replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const вызовыОбёртки = Array.from(текст.matchAll(new RegExp(имяОбёртки + '\\s*\\(', 'g')));
    for (const в of вызовыОбёртки) {
      const передСловом = текст.slice(Math.max(0, в.index - 12), в.index);
      if (/function\s+$/.test(передСловом)) continue; // это объявление, не вызов
      const окно = текст.slice(Math.max(0, в.index - ОКНО), в.index);
      if (словоУсловия.test(окно) || стоитПодУсловием(в.index)) return true;
    }
  }
  return false;
}

console.log('Проверка блока «В друзья» и реванша на экране результата (6 игр)');

for (const игра of ИГРЫ) {
  console.log('\n' + игра.имя + '  (' + игра.файл + ')');
  let текст;
  try {
    текст = fs.readFileSync(игра.файл, 'utf8');
  } catch (e) {
    проверить(false, 'файл читается: ' + e.message);
    continue;
  }

  const числоВызовов = (текст.match(/Сеть\??\.\s*кнопкаВДрузья\s*\(/g) || []).length;
  проверить(числоВызовов > 0, 'есть вызов window.Сеть.кнопкаВДрузья(...) на экране результата — найдено: ' + числоВызовов);

  const числоРеванш = (текст.match(/действие:\s*['"]ещё['"]/g) || []).length;
  проверить(числоРеванш > 0, 'есть отправка действия «ещё» (реванш по сети) — найдено: ' + числоРеванш);

  проверить(вызовЗащищёнУсловиемСети(текст), 'вызов «В друзья» стоит под условием сетевой игры (не рисуется в партии с ботом)');

  // Монополия: сервер поднимает отдельный признак «соперникУшёл» (когда за
  // столом никого не осталось) — кнопка реванша обязана его учитывать,
  // иначе после ухода соперника она навсегда висит disabled с надписью
  // «Ждём согласия…», хотя ждать больше некого.
  if (игра.имя === 'монополия') {
    проверить((текст.match(/соперникУшёл/g) || []).length > 0, 'кнопка реванша учитывает сетевой признак «соперникУшёл» (иначе висит disabled навсегда)');
  }
}

// --- «дурак»: живая проверка поведения через vm --------------------------
// Полностью поднять game.js (13000+ строк, звук, Telegram, DOM всей игры)
// непосильно — вместо этого достаём ИМЕННО те две функции, которые сами
// добавили для «В друзья», и гоняем их в песочнице с поддельными
// document/window. Так проверяем не текст, а настоящее поведение кода.
console.log('\nдурак — живая проверка в vm (один вызов на показ, без Сети — тишина)');
{
  const файлДурака = ИГРЫ[0].файл;
  const текст = fs.readFileSync(файлДурака, 'utf8');
  const началоФункций = текст.indexOf('function узелВДрузья()');
  const началоОбёртки = текст.indexOf('function освежитьКнопкуВДрузья');
  // Файл на CRLF (\r\n) — конец функции ищем regex'ом, а не indexOf('\n}\n').
  const хвостПослеОбёртки = началоОбёртки >= 0 ? текст.slice(началоОбёртки) : '';
  const совпКонца = хвостПослеОбёртки.match(/\r?\n\}\r?\n/);
  const конецФункций = совпКонца ? началоОбёртки + совпКонца.index + совпКонца[0].indexOf('}') : -1;

  if (началоФункций < 0 || началоОбёртки < 0 || конецФункций < 0) {
    проверить(false, 'нашлись исходники узелВДрузья/освежитьКнопкуВДрузья для живой проверки');
  } else {
    const исходник = текст.slice(началоФункций, конецФункций + 1); // включая саму «}»

    const песочница = { window: {} };
    песочница.document = {
      _узлы: {},
      getElementById(id) { return песочница.document._узлы[id] || null; },
      createElement(tag) {
        return {
          tagName: tag,
          _дети: [],
          set className(c) { this._class = c; },
          get className() { return this._class; },
          appendChild(реб) { this._дети.push(реб); return реб; },
        };
      },
    };
    // «экран-результата» — статичный узел разметки; кладём в него найденное
    // гнездо и запоминаем его же под id «гнездо-друзей», как в настоящем DOM.
    песочница.document._узлы['экран-результата'] = {
      appendChild(у) { песочница.document._узлы['гнездо-друзей'] = у; return у; },
    };
    песочница.эл = function (id) { return песочница.document.getElementById(id); };

    const контекст = vm.createContext(песочница);
    try {
      vm.runInContext(исходник, контекст, { filename: 'дурак-в-друзья.js' });

      // Сценарий 1: Сеть есть, итог показан — два ре-рендера подряд (как
      // бывает при частых обновлениях сетевого состояния стола).
      let вызовов = 0;
      песочница.window.Сеть = { кнопкаВДрузья() { вызовов++; return Promise.resolve(0); } };
      vm.runInContext('освежитьКнопкуВДрузья(); освежитьКнопкуВДрузья();', контекст);
      проверить(вызовов === 1, 'на повторных ре-рендерах одного и того же итога помощник вызван один раз (вызовов: ' + вызовов + ')');

      // Сценарий 2: новый показ итога, но Сети нет (партия с ботом либо
      // старая страница без общее/js/сеть.js) — вызова быть не должно и код не падает.
      вызовов = 0;
      песочница.window.Сеть = undefined;
      vm.runInContext('гнездоДрузейПоказано = false; освежитьКнопкуВДрузья();', контекст);
      проверить(вызовов === 0, 'без window.Сеть (партия с ботом/старая страница) помощник не вызывается и не падает (вызовов: ' + вызовов + ')');
    } catch (e) {
      проверить(false, 'исходник выполняется в vm без ошибок: ' + e.message);
    }
  }
}

console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);
process.exit(провалов > 0 ? 1 : 0);
