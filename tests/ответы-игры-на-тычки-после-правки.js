'use strict';

/* =====================================================================
   ПЯТЬ ПРОВЕРОК ПРО ОТВЕТЫ ИГРЫ НА НАЖАТИЯ.

   ЭТО НЕ АВТОПРОГОН ДЛЯ NODE. Файл вставляется в консоль браузера,
   когда игра уже открыта (http://127.0.0.1:8123/index.html), и запускается
   из меню — партию проверки начинают сами.

   ЧТО ИМЕННО ПРОВЕРЯЕТСЯ И ПОЧЕМУ ИМЕННО ЭТО

   1. На чужом ходу игра не врёт про руку.
      Человек тычет мимо карты, пока думает соперник. Первый раз игра
      говорит «Сейчас ходит соперник», второй — другими словами, иначе
      на телефоне это неотличимо от «игра не ответила». Вторые слова
      обязаны быть про очередь («Игра сама скажет, когда ваш ход»),
      а НЕ про подсветку: рука может быть полна козырей, черты на ней
      нет просто потому, что слово сейчас не наше. Проверяются все три
      порядка нажатий: мимо–мимо, по карте–мимо, мимо–по карте.

   2. Напоминание не прячется от того, кому оно нужно.
      Человек, которому нечем крыть, тычет в карты раз в секунду.
      Он должен видеть «Отбиться нечем — жмите „Беру“» при КАЖДОМ тычке,
      а не терять его на 2,4 секунды под словами отказа.

   3. Отказ живёт положенное время (2,4 секунды), а не мигает.

   4. «Хвост» своей же кнопки не получает отказа.
      Партию часто заканчивает своя кнопка, и палец после нажатия
      попадает в руку. Отвечать на это писком и вздрагиванием — значит
      ругать человека за удачное нажатие. Проверяем обе стороны: в первые
      150 мс после кнопки рука молчит, а позже — отвечает как обычно.

   5. Фраза «Карт у вас нет — пасуем за вас…» правда показывается.
      Она висит ту секунду с небольшим, пока игра собирается нажать «Пас»
      за человека с пустой рукой. Ловится наблюдателем, который читает
      строку подсказки каждые 40 мс: глазом такое пропустить легко.

   Ни одна строка сюда не переписана из игры «на память»: проверки читают
   то, что игра вправду нарисовала в строке подсказки.

   КАК ЗАПУСКАТЬ (звать по одному или все разом):
       проверкиТычков.чужойХод()      — пункт 1
       проверкиТычков.напоминание()   — пункты 2 и 3
       проверкиТычков.хвостКнопки()   — пункт 4
       проверкиТычков.пасуемЗаВас(4)  — пункт 5, до четырёх партий
       проверкиТычков.всё()
   ===================================================================== */

(function () {
  'use strict';

  const ждать = (мс) => new Promise((r) => setTimeout(r, мс));
  const строка = () => {
    const у = document.getElementById('подсказка-текст');
    return у ? (у.textContent || '') : '';
  };
  const видна = (id) => {
    const у = document.getElementById(id);
    return Boolean(у) && у.offsetParent !== null;
  };
  const жать = (id) => { const у = document.getElementById(id); if (у) у.click(); };
  const картыРуки = () => [].slice.call(document.querySelectorAll('#карты-человека .карта'));
  const пометокОтказа = () => document.querySelectorAll('#карты-человека .карта--отказ').length;
  /* Нажатие ставим настоящим событием мыши, а не вызовом функции игры:
     так проверяется в точности тот путь, по которому идёт живой палец. */
  const тапПо = (узел) => узел.dispatchEvent(new MouseEvent('click', { bubbles: true }));
  const тапМимо = () => тапПо(document.getElementById('рука-человека'));
  const партияИдёт = () => typeof партия !== 'undefined' && Boolean(партия) && !партия.завершена;

  const итоги = [];
  function записать(что, хорошо, подробности) {
    итоги.push({ что, хорошо, подробности });
    console.log((хорошо ? '  ХОРОШО  ' : '  ПЛОХО   ') + что + (подробности ? ' — ' + подробности : ''));
    return хорошо;
  }

  /** Начать партию с ботом, если её ещё нет. */
  async function завестиПартию() {
    if (партияИдёт()) return true;
    if (видна('кнопка-ещё')) { жать('кнопка-ещё'); await ждать(600); }
    else if (видна('кнопка-играть')) { жать('кнопка-играть'); await ждать(700); }
    return партияИдёт();
  }

  /** Один законный шаг за человека: положить карту или нажать кнопку. */
  async function сходитьЗаЧеловека() {
    const можно = document.querySelector('#карты-человека .карта--можно');
    if (можно) { тапПо(можно); await ждать(180); return 'карта'; }
    if (видна('кнопка-беру')) { жать('кнопка-беру'); await ждать(220); return 'беру'; }
    if (видна('кнопка-завершить')) { жать('кнопка-завершить'); await ждать(220); return 'бито'; }
    if (видна('кнопка-перевести')) { жать('кнопка-перевести'); await ждать(220); return 'перевод'; }
    await ждать(120);
    return '';
  }

  /** Довести партию до мига, когда слово у соперника. */
  async function дождатьсяЧужогоХода(секунд) {
    const край = Date.now() + (секунд || 40) * 1000;
    while (Date.now() < край) {
      if (!партияИдёт()) { await завестиПартию(); await ждать(200); continue; }
      const летит = typeof ждёмОтветаНаХод === 'function' && ждёмОтветаНаХод();
      if (!сейчасМойХод() && !летит) return true;
      if (сейчасМойХод() && !летит) { await сходитьЗаЧеловека(); continue; }
      await ждать(60);
    }
    return false;
  }

  /* ---- 1. Чужой ход: два нажатия подряд отвечают разными и честными словами ---- */
  async function чужойХод() {
    console.log('— Проверка 1: что игра отвечает на тычки, пока думает соперник');
    await завестиПартиюТихо();
    const случаи = [
      { имя: 'мимо → мимо', первый: тапМимо, второй: тапМимо },
      { имя: 'по карте → мимо', первый: тапПоПервойКарте, второй: тапМимо },
      { имя: 'мимо → по карте', первый: тапМимо, второй: тапПоПервойКарте }
    ];
    let всёХорошо = true;
    for (const случай of случаи) {
      if (!(await дождатьсяЧужогоХода(60))) {
        всёХорошо = записать('чужой ход: ' + случай.имя, false, 'не дождался чужого хода') && всёХорошо;
        continue;
      }
      await ждать(200);
      случай.первый(); await ждать(90);
      const первая = строка();
      await ждать(300);
      случай.второй(); await ждать(90);
      const вторая = строка();

      const разные = первая !== вторая;
      /* Главное: во вторых словах не должно быть разговора про руку —
         ни про подсветку, ни про «подходящей карты нет». Слово не наше,
         и рука тут ни при чём. */
      const проРуку = вторая.indexOf('Подходящей карты в руке') !== -1 ||
                      вторая.indexOf('Зелёная черта') !== -1;
      всёХорошо = записать('чужой ход: ' + случай.имя, разные && !проРуку,
        '1) ' + первая + '  2) ' + вторая) && всёХорошо;
    }
    return всёХорошо;
  }
  function тапПоПервойКарте() { const к = картыРуки()[0]; if (к) тапПо(к); }
  async function завестиПартиюТихо() { if (!(await завестиПартию())) console.log('  (партию завести не вышло)'); }

  /* ---- 2 и 3. Напоминание при частых тычках + срок жизни отказа ---- */
  async function напоминание() {
    console.log('— Проверка 2: видит ли подсказку тот, кому нечем крыть');
    await завестиПартиюТихо();
    const край = Date.now() + 170000;
    let найдено = false;
    while (Date.now() < край && !найдено) {
      if (!партияИдёт()) { await завестиПартию(); await ждать(200); continue; }
      if (!сейчасМойХод()) { await ждать(80); continue; }
      const подсвечено = document.querySelectorAll('#карты-человека .карта--можно').length;
      const нечемКрыть = фаза(партия) === 'защита' && подсвечено === 0 &&
                         партия.руки.человек.length > 0 && видна('кнопка-беру');
      if (!нечемКрыть) { await сходитьЗаЧеловека(); continue; }
      найдено = true;

      // тычем четыре раза подряд, раз в секунду, как это делает застрявший человек
      let всеСНапоминанием = true;
      const виденное = [];
      for (let n = 0; n < 4; n++) {
        тапПоПервойКарте();
        await ждать(120);
        const с = строка();
        виденное.push(с);
        if (с.indexOf('жмите «Беру»') === -1) всеСНапоминанием = false;
        await ждать(880);
        if (строка().indexOf('жмите «Беру»') === -1) всеСНапоминанием = false;
      }
      записать('нечем крыть: подсказка «жмите „Беру“» видна при каждом тычке',
        всеСНапоминанием, виденное.join(' | '));

      // срок жизни отказа: он обязан висеть около 2,4 секунды, а не мигать
      тапПоПервойКарте();
      const начало = Date.now();
      const былаСтрока = строка();
      let прожил = -1;
      for (let i = 0; i < 45; i++) {
        await ждать(100);
        if (строка() !== былаСтрока) { прожил = Date.now() - начало; break; }
      }
      записать('отказ живёт положенные 2,4 секунды', прожил >= 2000 && прожил <= 3200,
        прожил < 0 ? 'не сменился за 4,5 с' : 'прожил ' + прожил + ' мс');
    }
    if (!найдено) записать('нечем крыть: случай не встретился', false, 'за отведённое время');
    return найдено;
  }

  /* ---- 4. Хвост своей же кнопки ---- */
  async function хвостКнопки() {
    console.log('— Проверка 4: «хвост» кнопки не получает отказа');
    await завестиПартиюТихо();
    const край = Date.now() + 170000;
    while (Date.now() < край) {
      if (!партия) { await ждать(100); continue; }
      if (партия.завершена && партия.руки.человек.length > 0) break;
      if (партия.завершена) { await завестиПартию(); await ждать(200); continue; }
      if (партия.руки.человек.length === 0) { await ждать(60); continue; }
      if (!сейчасМойХод()) { await ждать(80); continue; }
      await сходитьЗаЧеловека();
    }
    if (!(партия && партия.завершена && партия.руки.человек.length > 0)) {
      return записать('хвост кнопки', false, 'не дождался конца партии с картами в руке');
    }
    const карта = картыРуки()[0];
    const доТычка = строка();
    /* Глухоту ставим ровно так, как её ставит любая кнопка игры
       (см. ГЛУХОТА_ПОСЛЕ_КНОПКИ). Ждать живого совпадения «своя кнопка
       закончила партию» пришлось бы десятки партий. */
    рукаГлухаДо = Date.now() + 150;
    тапПо(карта);
    await ждать(90);
    const молчит = строка() === доТычка && пометокОтказа() === 0;
    записать('в первые 150 мс после кнопки рука молчит', молчит,
      'строка: ' + строка() + ', вздрагиваний: ' + пометокОтказа());

    await ждать(320);
    тапПо(карта);
    await ждать(90);
    const отвечает = строка() !== доТычка && пометокОтказа() > 0;
    записать('позже глухоты игра отвечает как обычно', отвечает,
      'строка: ' + строка() + ', вздрагиваний: ' + пометокОтказа());
    return молчит && отвечает;
  }

  /* ---- 5. «Карт у вас нет — пасуем за вас…» ----

     СЛУЧАЙ РЕДКИЙ, и это надо помнить, читая красную строку. Фраза
     приходит только тогда, когда рука человека опустела, а слово ещё
     у него: это примерно раз в две партии. Замерено: за одну четвёрку
     партий она встретилась дважды, за следующую — ни разу. Поэтому
     «не встретилась» здесь НЕ значит «сломано»; значит «прогоните ещё
     раз или дайте больше времени»:

         проверкиТычков.пасуемЗаВас(8, 300)   // до 8 партий, до 5 минут  */
  async function пасуемЗаВас(партийМакс, секунд) {
    console.log('— Проверка 5: показывается ли «Карт у вас нет — пасуем за вас…»');
    await завестиПартиюТихо();
    /* Наблюдатель нужен обязательно: фраза висит чуть больше секунды,
       а между двумя шагами проверки может пройти больше. */
    const виденное = [];
    let прошлая = '';
    const смотритель = setInterval(function () {
      const с = строка();
      if (с !== прошлая) { прошлая = с; виденное.push(с); }
    }, 40);

    const край = Date.now() + (секунд || 170) * 1000;
    const нужноПартий = партийМакс || 4;
    let партий = 0;
    let нашлись = [];
    while (Date.now() < край && партий < нужноПартий && нашлись.length === 0) {
      нашлись = виденное.filter((с) => с.indexOf('пасуем за вас') !== -1);
      if (!партия) { await ждать(100); continue; }
      if (партия.завершена) { if (видна('кнопка-ещё')) { жать('кнопка-ещё'); партий++; await ждать(450); } else await ждать(150); continue; }
      // Рука пуста — не трогаем НИЧЕГО: «Пас» должна нажать сама игра
      if (партия.руки.человек.length === 0) { await ждать(50); continue; }
      if (!сейчасМойХод()) { await ждать(80); continue; }
      await сходитьЗаЧеловека();
    }
    clearInterval(смотритель);
    нашлись = виденное.filter((с) => с.indexOf('пасуем за вас') !== -1);
    return записать('фраза «Карт у вас нет — пасуем за вас…» показана',
      нашлись.length > 0,
      нашлись.length > 0
        ? нашлись[0]
        : 'не встретилась за ' + партий + ' партий — случай редкий, прогоните ещё раз');
  }

  async function всё() {
    итоги.length = 0;
    await чужойХод();
    await напоминание();
    await хвостКнопки();
    await пасуемЗаВас(4);
    const плохих = итоги.filter((и) => !и.хорошо).length;
    console.log(плохих === 0
      ? '=== Итог: все ' + итоги.length + ' проверок прошли ==='
      : '=== Итог: не прошло ' + плохих + ' из ' + итоги.length + ' ===');
    return { всего: итоги.length, плохих, итоги };
  }

  window.проверкиТычков = { чужойХод, напоминание, хвостКнопки, пасуемЗаВас, всё };
  console.log('Проверки готовы: проверкиТычков.всё() — или по одной, см. начало файла.');
})();
