/* Страница без ?сервер= в среде разработки решает, что «сервер игры»
   живёт на боевом 127.0.0.1:8790 (js/сеть.js, запасной адрес) — и три
   фоновых скрипта, которых на момент написания сценария ещё не было
   (js/пульс.js, js/популярность.js, js/мой-аватар.js), реально стучатся
   туда на путях /статистика, /пульс, /мой-аватар. Боевой 8790 в прогоне
   проверки не слушается — requestfailed красит консоль. Даём странице
   заведомо выдуманный адрес (порт 9 — тот же приём, что в tests/браузер-
   рейтинг-круг-друзей.js) и перехватываем все четыре двери одним route. */
const АДРЕС_ИГРЫ_ВЫДУМАННЫЙ = 'http://127.0.0.1:9';

function json(route, тело) {
  return route.fulfill({ status: 200, contentType: 'application/json; charset=utf-8', body: JSON.stringify(тело) });
}
const ОТВЕТ_РЕЙТИНГА_ПУСТОЙ = { ок: true, узналиВас: true, игра: 'дурак', всего: 0, яВТаблице: false, я: null, верхушка: [], вокругМеня: [] };
async function диспетчерФоновыхДверей(route, request, адрес) {
  if (/\/рейтинг(?:\?|$)/.test(адрес || '')) { await json(route, ОТВЕТ_РЕЙТИНГА_ПУСТОЙ); return; }
  await json(route, { ок: false });
}

let BASE_URL = process.env.TEST_URL || '';
let ошибок = 0;
let тестов = 0;

const СЛОМАТЬ = process.argv.includes('--сломать');
