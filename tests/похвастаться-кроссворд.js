/** Кладёт в память почти решённую партию и возвращает номер недостающей клетки. */
function подложитьПартию(параметры) {
  const р = window.Nonogram;
  const состояние = р.create(window.NonogramPuzzles.find(function (п) { return п.level === 'easy'; }));
  // Из решения убираем первые закрашенные клетки: одну (партия кончится кликом) или две (не кончится).
  const закрашенные = [];
  состояние.solution.forEach(function (в, и) { if (в === 1) закрашенные.push(и); });
  const нужная = закрашенные[0];
  const убранные = закрашенные.slice(0, параметры.недостаёт);
  состояние.board = состояние.solution.map(function (в, и) { return в === 1 && убранные.indexOf(и) === -1 ? 1 : 0; });
  состояние.seconds = 125;
  состояние.hints = параметры.подсказок;
  состояние.checks = параметры.проверок;
  localStorage.setItem('nonogram-game-v1', JSON.stringify(состояние));
  return нужная;
}

async function случай(браузер, порт, настройка, подмена) {
  const страница = await браузер.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
  const ошибки = [];
  страница.on('pageerror', function (е) { ошибки.push(е.message); });
  страница.on('console', function (с) {
    if (с.type() === 'error' && !/telegram\.org|Failed to load resource/i.test(с.text())) ошибки.push(с.text());
  });
  if (подмена) {
    await страница.route('**/игры/nonogram/nonogram-ui.js*', function (путь) {
      путь.fulfill({ status: 200, contentType: 'text/javascript; charset=utf-8', body: подмена });
    });
  }
  if (настройка.телеграм) await подготовитьПодделку(страница, { подпись: 'query_id=проверка&user=1' });
  else await безTelegram(страница);
  const адрес = 'http://127.0.0.1:' + порт + '/nonogram.html';
  await страница.goto(адрес);
  const нужная = await страница.evaluate(подложитьПартию, настройка);
  await страница.reload();
  // Шпионы ставим после загрузки страницы: ярлык.js при загрузке сам кладёт window.Ярлык.
  await страница.evaluate(function () {
    window.__хвастовство = [];
    window.__ярлык = [];
    window.Сеть = window.Сеть || {};
    window.Сеть.похвастаться = function (описание) { window.__хвастовство.push(описание); return Promise.resolve({ отправлено: true }); };
    window.Ярлык = { партияСыграна: function (игра) { window.__ярлык.push(игра); } };
  });
  await страница.locator('#continue').click();
  await страница.locator('.pixel[data-index="' + нужная + '"]').waitFor({ state: 'visible', timeout: 5000 });
  await страница.locator('.pixel[data-index="' + нужная + '"]').click();
  return { страница: страница, ошибки: ошибки };
}

async function прогон(подмена) {
  всего = 0; провалов = 0;
  const сервер = await поднятьСервер();
  const порт = сервер.address().port;
  const браузер = await chromium.launch();
  try {
    const кнопка = function (с) { return с.страница.locator('#dialog-body button', { hasText: 'Похвастаться' }); };
    const дальше = function (с) { return с.страница.locator('#dialog-body button', { hasText: 'Следующий рисунок' }); };

    console.log('Случай 1: победа в Telegram, без подсказок');
    const победа = await случай(браузер, порт, { телеграм: true, недостаёт: 1, подсказок: 0, проверок: 0 }, подмена);
    await дальше(победа).waitFor({ state: 'visible', timeout: 5000 });
    проверить(await дальше(победа).count() === 1, 'окно итога открыто («Следующий рисунок» есть)');
    проверить(await кнопка(победа).count() === 1 && await кнопка(победа).isVisible(), 'кнопка «Похвастаться» видна');
    await победа.страница.screenshot({ path: path.join(ПАПКА_СНИМКОВ, 'кроссворд-похвастаться.png') });
    const ярлыкДо = await победа.страница.evaluate(function () { return window.__ярлык.slice(); });
    проверить(ярлыкДо.length === 1 && ярлыкДо[0] === 'японский-кроссворд', 'Ярлык.партияСыграна позвана ровно один раз с «японский-кроссворд»');
    if (await кнопка(победа).count() === 1) await кнопка(победа).click();
    const звонки = await победа.страница.evaluate(function () { return window.__хвастовство; });
    проверить(звонки.length === 1, 'дверь Сеть.похвастаться позвана ровно один раз');
    const о = звонки[0] || {};
    проверить(о.игра === 'японский-кроссворд' && о.исход === 'победа' && о.мера === 'секунд', 'описание: игра, исход «победа», мера «секунд»');
    проверить(Number.isInteger(о.значение) && о.значение >= 125 && о.значение < 140, 'значение — целые секунды партии (около 125), у нас ' + о.значение);
    проверить(!('режим' in о), 'поля «режим» в описании нет (у игры режимов нет в реестре)');
    проверить(Object.keys(о).length === 4, 'в описании ровно четыре поля');
    const ярлыкПосле = await победа.страница.evaluate(function () { return window.__ярлык.length; });
    проверить(ярлыкПосле === 1, 'после нажатия кнопки партия не засчитана второй раз');
    проверить(победа.ошибки.length === 0, 'консоль чистая' + (победа.ошибки.length ? ': ' + победа.ошибки[0] : ''));
    await победа.страница.close();

    console.log('Случай 2: победа без Telegram');
    const безТГ = await случай(браузер, порт, { телеграм: false, недостаёт: 1, подсказок: 0, проверок: 0 }, подмена);
    await дальше(безТГ).waitFor({ state: 'visible', timeout: 5000 });
    проверить(await дальше(безТГ).count() === 1, 'окно итога открыто');
    проверить(await кнопка(безТГ).count() === 0, 'кнопки «Похвастаться» нет');
    await безТГ.страница.close();

    console.log('Случай 3: победа с подсказкой');
    const сПодсказкой = await случай(браузер, порт, { телеграм: true, недостаёт: 1, подсказок: 1, проверок: 0 }, подмена);
    await дальше(сПодсказкой).waitFor({ state: 'visible', timeout: 5000 });
    проверить(await дальше(сПодсказкой).count() === 1, 'окно итога открыто');
    проверить(await кнопка(сПодсказкой).count() === 0, 'кнопки «Похвастаться» нет');
    await сПодсказкой.страница.close();

    console.log('Случай 4: победа с проверкой');
    const сПроверкой = await случай(браузер, порт, { телеграм: true, недостаёт: 1, подсказок: 0, проверок: 1 }, подмена);
    await дальше(сПроверкой).waitFor({ state: 'visible', timeout: 5000 });
    проверить(await дальше(сПроверкой).count() === 1, 'окно итога открыто');
    проверить(await кнопка(сПроверкой).count() === 0, 'кнопки «Похвастаться» нет');
    await сПроверкой.страница.close();

    console.log('Случай 5: не решено');
    const нереш = await случай(браузер, порт, { телеграм: true, недостаёт: 2, подсказок: 0, проверок: 0 }, подмена);
    // Клик закрасил одну из двух недостающих клеток: партия идёт, итога быть не должно.
    await нереш.страница.waitForTimeout(500);
    const клетка = await нереш.страница.evaluate(function () { return document.querySelectorAll('.pixel.filled').length; });
    проверить(клетка > 0, 'партия на экране, клик по клетке дошёл (закрашенных клеток: ' + клетка + ')');
    проверить(await нереш.страница.locator('#dialog[open]').count() === 0, 'окно итога не открылось');
    проверить(await кнопка(нереш).count() === 0, 'кнопки «Похвастаться» нет');
    const ярлыкНереш = await нереш.страница.evaluate(function () { return window.__ярлык.length; });
    проверить(ярлыкНереш === 0, 'Ярлык.партияСыграна не позвана');
    await нереш.страница.close();
  } finally {
    await браузер.close();
    сервер.close();
  }
  return провалов;
}

/* ---------- Ломающие прогоны ---------- */

const УСЛОВИЕ_ПОМОЩИ = '!state.completed||state.hints||state.checks||';
const УСЛОВИЕ_TELEGRAM = '||!inTelegram||';

async function сломать() {
  const исходник = fs.readFileSync(path.join(ПРОЕКТ, ИМЯ_ЭКРАНА), 'utf8');
  for (const условие of [УСЛОВИЕ_ПОМОЩИ, УСЛОВИЕ_TELEGRAM]) {
    const сколько = исходник.split(условие).length - 1;
    if (сколько !== 1) { console.log('ПЛОХО — строка порчи «' + условие + '» найдена ' + сколько + ' раз, нужно ровно 1'); process.exit(1); }
  }
  console.log('Контрольный прогон по целой копии (обязан быть зелёным)');
  const контроль = await прогон(исходник);
  console.log('\nЛомающий прогон (а): копия без условий «без подсказок и проверок» (обязан покраснеть)');
  const безПомощи = await прогон(исходник.replace(УСЛОВИЕ_ПОМОЩИ, ''));
  console.log('\nЛомающий прогон (б): копия без условия «внутри Telegram» (обязан покраснеть)');
  const безТелеграма = await прогон(исходник.replace(УСЛОВИЕ_TELEGRAM, '||'));
  console.log('\nКонтроль: провалов ' + контроль + ' (нужно 0); без помощи: ' + безПомощи + ' (нужно >0); без Telegram: ' + безТелеграма + ' (нужно >0)');
  process.exit(контроль === 0 && безПомощи > 0 && безТелеграма > 0 ? 0 : 1);
}

(async function () {
  if (process.argv.includes('--сломать')) return сломать();
  const красных = await прогон(null);
  console.log('\nИтого проверок: ' + всего + ', провалов: ' + красных);
  process.exit(красных ? 1 : 0);
})().catch(function (е) { console.log('Проверка упала: ' + (е && е.stack || е)); process.exit(1); });
