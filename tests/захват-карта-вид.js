/* =====================================================================
   Проверка раскладки карты «Захвата» (этап В4).
   Запуск:  node tests/захват-карта-вид.js
   Довод:   --файл <путь>  — взять копию js/захват-карта-вид.js вместо настоящей
                             (рядом с копией должен лежать захват-карты.js)
   Порча:   --сломать      — на КОПИЯХ во временной папке портит файл разными способами
                             и требует провала в каждом (настоящий файл не трогается).
   Идея: холст поддельный — записывает и вызовы, и присваивания свойств. Картинки тоже
   поддельные (рисунков Кодекса пока нет). Разрешено только drawImage, save, restore,
   setTransform, clearRect, rotate, translate, scale и свойство globalAlpha.
   Ожидаемые кромки, границы краёв и места шайб считаются здесь заново, из сетки и
   из векторов граней, а не из того, что делает проверяемый файл.
   ===================================================================== */
