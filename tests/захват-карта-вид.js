    // (за гранью k+1 та же область ? 2 : 0); грань 0 — это 6, грань 7 — это 1.
    function рядКадра(ряд, стб, грань, номер) {
      const перед = грань === 1 ? 6 : грань - 1;
      const после = грань === 6 ? 1 : грань + 1;
      return (сосед(ряд, стб, перед) === номер ? 1 : 0) + (сосед(ряд, стб, после) === номер ? 2 : 0);
    }
    const крайПоОбласти = {};
    карта.края.forEach(function (к) { к.области.forEach(function (н) { крайПоОбласти[н] = к.название; }); });
    return {
      карта: карта, поле: поле, s: s, w: w, h: h, шаг: шаг, центр: центр, сосед: сосед, рядКадра: рядКадра,
      клетки: клетки, клеткаВТочке: клеткаВТочке, край: крайПоОбласти,
      ширина: ширина, высота: (0.75 * карта.рядов + 0.25) * h + (ВЕРХ + НИЗ) * s
    };
