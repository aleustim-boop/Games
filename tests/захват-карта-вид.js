    проверить(ожидаемыеГраницы.length * 2 === разныхКраёвПарГраней, ключКарты + ': половина граней — ' + ожидаемыеГраницы.length + ' из ' + разныхКраёвПарГраней);
    проверить(JSON.stringify(ключи(р.слои['границы-краёв'], ['ряд', 'стб', 'грань'])) === JSON.stringify(ключи(ожидаемыеГраницы, ['ряд', 'стб', 'грань'])),
      ключКарты + ': границы краёв ' + р.слои['границы-краёв'].length + ' не совпали с ожидаемыми ' + ожидаемыеГраницы.length);
    р.слои['границы-краёв'].forEach(function (э) {
      проверить(э.рисунок === 'граница-края' && э.кадр === э.грань - 2 && э.источник.x === (э.грань - 2) * КАДР_Ш &&
        э.источник.y === 0 && э.источник.ширина === 288,
        ключКарты + ': граница края — не тот кадр (грань ' + э.грань + ' кадр ' + э.кадр + ' y ' + э.источник.y + '); ряд у границы всегда один (0)');
    });

    // Море в раскладку НЕ входит: его плитки считает нарисовать() по холсту (вне зума и сдвига).
