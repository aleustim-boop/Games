function сломать() {
  const исходник = fs.readFileSync(ФАЙЛ_ВИДА, 'utf8');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-карта-вид-'));
  let подвело = 0;
  ПОРЧИ.forEach(function (порча, и) {
    let текст = исходник;
    let применилась = true;
    порча.правки.forEach(function (правка) {
      const частей = исходник.split(правка[0]).length - 1;
      if (частей !== 1) {
        console.log('ПОРЧА НЕ ПРИМЕНИЛАСЬ (' + порча.имя + '): найдено мест — ' + частей + ' (нужно ровно одно) для «' + правка[0].slice(0, 60) + '»');
        применилась = false;
        return;
      }
      текст = текст.replace(правка[0], function () { return правка[1]; });
    });
    if (!применилась) { подвело++; return; }
    const каталог = path.join(папка, 'копия-' + (и + 1));
    fs.mkdirSync(каталог);
    fs.copyFileSync(ФАЙЛ_КАРТ, path.join(каталог, 'захват-карты.js'));
    const копия = path.join(каталог, 'захват-карта-вид.js');
    fs.writeFileSync(копия, текст, 'utf8');
    const итог = spawnSync(process.execPath, [__filename, '--файл', копия], { encoding: 'utf8', timeout: 300000 });
    const вывод = итог.stdout || '';
    const строка = (вывод.match(/Итого проверок: \d+, провалов: \d+/) || ['(итога нет)'])[0];
    const покраснела = итог.status === 1 && /провалов: [1-9]/.test(строка);
    const первый = вывод.split('\n').filter(function (с) { return /^ПРОВАЛ/.test(с); })[0] || '';
    console.log((покраснела ? 'КРАСНЕЕТ' : 'НЕ КРАСНЕЕТ') + ' — ' + порча.имя + ' [' + строка + '] ' + первый.slice(0, 120));
    if (!покраснела) подвело++;
  });
  console.log('Порч всего: ' + ПОРЧИ.length + ', не покраснело: ' + подвело + ' (копии в ' + папка + ')');
  process.exit(подвело === 0 ? 0 : 1);
}

function запустить() {
  const индексФайла = аргументы.indexOf('--файл');
  const путьВида = индексФайла !== -1 && аргументы[индексФайла + 1]
    ? path.resolve(аргументы[индексФайла + 1])
    : ФАЙЛ_ВИДА;

  let проверок = 0;
  let провалов = 0;
  function проверить(условие, что) {
    проверок++;
    if (!условие) {
      провалов++;
      console.log('ПРОВАЛ: ' + что);
    }
  }

  Promise.resolve().then(function () {
    return проверки(путьВида, проверить);
  }).catch(function (ошибка) {
    // Падение проверяемого файла — тоже провал, а не «пропуск».
    проверок++;
    провалов++;
    console.log('ПРОВАЛ: файл упал с ошибкой — ' + (ошибка && ошибка.stack ? ошибка.stack.split('\n').slice(0, 3).join(' | ') : ошибка));
  }).then(function () {
    console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
    process.exit(провалов ? 1 : 0);
  });
}

