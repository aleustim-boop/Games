// Размер webp из заголовка файла (три вида: VP8X, VP8 с потерями, VP8L без потерь). Нет — null.
function размерWebp(буфер) {
  if (буфер.length < 30 || буфер.toString('latin1', 0, 4) !== 'RIFF' || буфер.toString('latin1', 8, 12) !== 'WEBP') return null;
  const вид = буфер.toString('latin1', 12, 16);
  if (вид === 'VP8X') {
    return { ширина: 1 + буфер.readUIntLE(24, 3), высота: 1 + буфер.readUIntLE(27, 3) };
  }
  if (вид === 'VP8 ') {
    return { ширина: буфер.readUInt16LE(26) & 0x3fff, высота: буфер.readUInt16LE(28) & 0x3fff };
  }
  if (вид === 'VP8L') {
    const биты = буфер.readUInt32LE(21);
    return { ширина: 1 + (биты & 0x3fff), высота: 1 + ((биты >>> 14) & 0x3fff) };
  }
  return null;
}

