function проверки(путьВида, проверить) {
  const Вид = require(путьВида);
  const Карты = require(ФАЙЛ_КАРТ);
  const Правила = require(path.join(ПАПКА_ПРОЕКТА, 'js', 'захват-правила.js'));
  const ШИРИНА = 358;

  // ---- Состояния: шесть мест, ничьи области и ничья столица; вся палитра на обеих картах ----
  const ИГРОКИ = ['а', 'б', 'в', 'г', 'д', 'е'];
  function состояниеШестерых(ключКарты) {
    const карта = Карты.КАРТЫ[ключКарты];
    const хозяева = [0];
    карта.области.forEach(function (о) {
      хозяева[о.номер] = о.номер % 7 === 0 ? null : ИГРОКИ[(о.номер - 1) % 6];
    });
    return {
      карта: ключКарты,
      игроки: ИГРОКИ.slice(),
      хозяева: хозяева,
      // Области 1–3 — столицы своих хозяев, 7 — ничья столица (хозяин сдался).
      столицы: [{ область: 1, хозяинНаСтарте: 'а' }, { область: 2, хозяинНаСтарте: 'б' },
        { область: 3, хозяинНаСтарте: 'в' }, { область: 7, хозяинНаСтарте: 'ж' }]
    };
  }

  // ---- Своя сетка и свой расчёт геометрии (не из проверяемого файла) ----
  function разобратьКарту(ключКарты) {
    const карта = Карты.КАРТЫ[ключКарты];
    const поле = карта.сетка.map(function (с) {
      return с.split(' ').map(function (б) { return Карты.БУКВЫ.indexOf(б) + 1; });
    });
    const w = ШИРИНА / (карта.столбцов + 0.5);
    const h = w * 296 / 256;
    const шаг = 0.75 * h;
    function центр(ряд, стб) {
      return { x: w * (стб + 0.5) + (ряд % 2 === 1 ? w / 2 : 0), y: h / 2 + ряд * шаг };
    }
    const порогКлетки = {};
    поле.forEach(function (строка, ряд) {
      строка.forEach(function (н, стб) {
        const ц = центр(ряд, стб);
        порогКлетки[Math.round(ц.x * 100) + ',' + Math.round(ц.y * 100)] = { ряд: ряд, стб: стб, номер: н };
      });
    });
    // Векторы граней 1…6 от центра клетки до центра соседа.
    const векторы = [[w / 2, -шаг], [w, 0], [w / 2, шаг], [-w / 2, шаг], [-w, 0], [-w / 2, -шаг]];
    function сосед(ряд, стб, грань) {
      const ц = центр(ряд, стб);
      const в = векторы[грань - 1];
      const найден = порогКлетки[Math.round((ц.x + в[0]) * 100) + ',' + Math.round((ц.y + в[1]) * 100)];
      return найден ? найден.номер : 0;
    }
    const крайПоОбласти = {};
    карта.края.forEach(function (к) { к.области.forEach(function (н) { крайПоОбласти[н] = к.название; }); });
    return { карта: карта, поле: поле, w: w, h: h, шаг: шаг, центр: центр, сосед: сосед, край: крайПоОбласти };
  }

  function ключи(список, поля) {
    return список.map(function (э) { return поля.map(function (п) { return э[п]; }).join('/'); }).sort();
  }

  ['материк', 'остров'].forEach(function (ключКарты) {
    const г = разобратьКарту(ключКарты);
    const партия = состояниеШестерых(ключКарты);
    const р = Вид.собратьРаскладку(партия, { ширина: ШИРИНА });
    const тела = р.слои['тела'];

    // Сколько сот на карте — считаем сами по строкам сетки.
    let сот = 0;
    г.поле.forEach(function (с) { с.forEach(function (н) { if (н) сот++; }); });
    проверить(сот > 50, ключКарты + ': в сетке найдены соты (' + сот + ')');
    проверить(тела.length === сот, ключКарты + ': кадров тела ' + тела.length + ', сот в сетке ' + сот);

    // Шаг соты: ТЗ 8.4.1 — 34 px у Материка и 42 px у Острова на 358 px.
    проверить(Math.abs(р.геометрия.ширинаСоты - г.w) < 1e-9, ключКарты + ': ширина соты ' + р.геометрия.ширинаСоты);
    проверить(Math.round(г.w) === (ключКарты === 'материк' ? 34 : 42), ключКарты + ': ширина соты по ТЗ');

    // Тело стоит так, что центр шестиугольника кадра (144, 164) лежит в центре клетки (4.3 п.1).
    const м = г.w / 256;
    const неТам = тела.filter(function (э) {
      const ц = г.центр(э.ряд, э.стб);
      return Math.abs(э.куда.x + 144 * м - ц.x) > 1e-6 || Math.abs(э.куда.y + 164 * м - ц.y) > 1e-6 ||
        Math.abs(э.куда.ширина - 288 * м) > 1e-6 || Math.abs(э.куда.высота - 328 * м) > 1e-6 ||
        э.кадр !== 0 || э.источник.x !== 0 || э.источник.ширина !== 288 || э.источник.высота !== 328;
    });
    проверить(неТам.length === 0, ключКарты + ': тела вне места или не кадр 0 (' + неТам.length + ')');
    // Нечётные ряды сдвинуты на полсоты.
    const первоеЧётное = тела.find(function (э) { return э.ряд === 2 && э.стб === 1; });
    const первоеНечётное = тела.find(function (э) { return э.ряд === 1 && э.стб === 1; });
    проверить(!!первоеЧётное && !!первоеНечётное &&
      Math.abs((первоеНечётное.куда.x - первоеЧётное.куда.x) - г.w / 2) < 1e-6,
      ключКарты + ': нечётный ряд сдвинут на полсоты');

    // Цвет листа — по месту хозяина; все шесть цветов и дым встретились.
    const листы = {};
    тела.forEach(function (э) {
      const ожидаемый = (function () {
        const х = партия.хозяева[э.область];
        return 'сота-' + (х === null ? 'дым' : ['коралл', 'лазурь', 'янтарь', 'аметист', 'бирюза', 'роза'][ИГРОКИ.indexOf(х)]);
      })();
      листы[э.рисунок] = true;
      проверить(э.рисунок === ожидаемый, ключКарты + ': область ' + э.область + ' лист ' + э.рисунок + ' вместо ' + ожидаемый);
    });
    проверить(Object.keys(листы).length === 7, ключКарты + ': в телах листов ' + Object.keys(листы).length + ' из 7');

    // Кромки: ровно на грани, за которыми другая область или море (ожидание считаем по векторам).
    const ожидаемыеКромки = [];
    const ожидаемыеГраницы = [];
    let разныхКраёвПарГраней = 0;
    г.поле.forEach(function (строка, ряд) {
      строка.forEach(function (номер, стб) {
        if (!номер) return;
        for (let грань = 1; грань <= 6; грань++) {
          const за = г.сосед(ряд, стб, грань);
          if (за !== номер) ожидаемыеКромки.push({ ряд: ряд, стб: стб, грань: грань });
          if (за && за !== номер && г.край[за] !== г.край[номер]) {
            разныхКраёвПарГраней++;
            if (грань === 2 || грань === 3 || грань === 4) ожидаемыеГраницы.push({ ряд: ряд, стб: стб, грань: грань });
          }
        }
      });
    });
    проверить(ожидаемыеКромки.length > 200, ключКарты + ': ожидаемых кромок найдено ' + ожидаемыеКромки.length);
    проверить(JSON.stringify(ключи(р.слои['кромки'], ['ряд', 'стб', 'грань'])) === JSON.stringify(ключи(ожидаемыеКромки, ['ряд', 'стб', 'грань'])),
      ключКарты + ': кромки ' + р.слои['кромки'].length + ' не совпали с ожидаемыми ' + ожидаемыеКромки.length);
    // Лист кромки — тот же, что у тела этой же клетки (цвет хозяина, а не соседа).
    const телоКлетки = {};
    тела.forEach(function (э) { телоКлетки[э.ряд + '/' + э.стб] = э; });
    let кромокСЛистомТела = 0;
    р.слои['кромки'].forEach(function (э) {
      const тело = телоКлетки[э.ряд + '/' + э.стб];
      if (тело && э.рисунок === тело.рисунок) кромокСЛистомТела++;
      проверить(э.кадр === э.грань && э.источник.x === э.грань * 288, ключКарты + ': кадр кромки не равен номеру грани');
    });
    проверить(р.слои['кромки'].length > 100 && кромокСЛистомТела === р.слои['кромки'].length,
      ключКарты + ': кромок с листом своего тела ' + кромокСЛистомТела + ' из ' + р.слои['кромки'].length);

    // Граница края: один раз на общую грань (каждая общая грань видна с двух сторон — делим пополам).
    проверить(ожидаемыеГраницы.length > 5, ключКарты + ': ожидаемых границ краёв найдено ' + ожидаемыеГраницы.length);
    проверить(ожидаемыеГраницы.length * 2 === разныхКраёвПарГраней, ключКарты + ': половина граней — ' + ожидаемыеГраницы.length + ' из ' + разныхКраёвПарГраней);
    проверить(JSON.stringify(ключи(р.слои['границы-краёв'], ['ряд', 'стб', 'грань'])) === JSON.stringify(ключи(ожидаемыеГраницы, ['ряд', 'стб', 'грань'])),
      ключКарты + ': границы краёв ' + р.слои['границы-краёв'].length + ' не совпали с ожидаемыми ' + ожидаемыеГраницы.length);
    р.слои['границы-краёв'].forEach(function (э) {
      проверить(э.рисунок === 'граница-края' && э.кадр === э.грань - 2 && э.источник.ширина === 288,
        ключКарты + ': граница края — не тот кадр (грань ' + э.грань + ' кадр ' + э.кадр + ')');
    });

    // Море: плитки покрывают карту без дыр и без нахлёста; рисунок растянут вдвое (512 -> 256).
    let площадь = 0;
    р.слои['море'].forEach(function (э) {
      площадь += э.куда.ширина * э.куда.высота;
      проверить(э.рисунок === 'море-плитка' && Math.abs(э.источник.ширина - 2 * э.куда.ширина) < 1e-6 &&
        Math.abs(э.источник.высота - 2 * э.куда.высота) < 1e-6 && э.источник.x >= 0 && э.источник.x + э.источник.ширина <= 512 + 1e-6 &&
        э.источник.y >= 0 && э.источник.y + э.источник.высота <= 512 + 1e-6, ключКарты + ': плитка моря не в границах рисунка');
    });
    проверить(р.слои['море'].length >= 2, ключКарты + ': плиток моря ' + р.слои['море'].length);
    проверить(Math.abs(площадь - р.геометрия.ширина * р.геометрия.высота) < 1e-3, ключКарты + ': море покрывает ' + площадь + ' из ' + р.геометрия.ширина * р.геометрия.высота);

    // Порядок слоёв: список идёт снизу вверх.
    const порядок = ['море', 'тела', 'кромки', 'границы-краёв', 'выбор', 'цели', 'стрелки'];
    проверить(JSON.stringify(Вид.СЛОИ) === JSON.stringify(порядок), ключКарты + ': порядок слоёв ' + Вид.СЛОИ.join(' > '));
    let последний = -1;
    let порядокВерен = true;
    р.список.forEach(function (э) {
      const н = порядок.indexOf(э.слой);
      if (н === -1 || н < последний) порядокВерен = false;
      последний = Math.max(последний, н);
    });
    проверить(порядокВерен && р.список.length === тела.length + р.слои['кромки'].length + р.слои['границы-краёв'].length + р.слои['море'].length,
      ключКарты + ': список не по порядку слоёв или с лишним');

    // Шайбы: по одной на область, на центральной соте (ближайшей к среднему центров).
    проверить(р.шайбы.length === г.карта.области.length, ключКарты + ': шайб ' + р.шайбы.length + ' из ' + г.карта.области.length);
    р.шайбы.forEach(function (ш) {
      const соты = [];
      г.поле.forEach(function (строка, ряд) {
        строка.forEach(function (н, стб) { if (н === ш.область) соты.push({ ряд: ряд, стб: стб, ц: г.центр(ряд, стб) }); });
      });
      const сх = соты.reduce(function (а, с) { return а + с.ц.x; }, 0) / соты.length;
      const су = соты.reduce(function (а, с) { return а + с.ц.y; }, 0) / соты.length;
      соты.forEach(function (с) { с.р = Math.pow(с.ц.x - сх, 2) + Math.pow(с.ц.y - су, 2); });
      соты.sort(function (а, б) {
        const разница = Math.abs(а.р - б.р) < 1e-6 ? 0 : а.р - б.р;
        return разница || а.ряд - б.ряд || а.стб - б.стб;
      });
      проверить(ш.ряд === соты[0].ряд && ш.стб === соты[0].стб && Math.abs(ш.x - соты[0].ц.x) < 1e-6 && Math.abs(ш.y - соты[0].ц.y) < 1e-6,
        ключКарты + ': шайба области ' + ш.область + ' не на центральной соте');
    });
    // Пилюля — якорь у верха шайбы.
    проверить(р.пилюли.length === р.шайбы.length && р.пилюли.every(function (п, и) {
      return п.область === р.шайбы[и].область && Math.abs(п.x - р.шайбы[и].x) < 1e-9 &&
        Math.abs(п.y - (р.шайбы[и].y - р.шайбы[и].размер / 2)) < 1e-9;
    }), ключКарты + ': якоря пилюль');
    // Столицы: 1, 2, 3 — гранёные со значком в цвете хозяина; 7 — ничья, без гранёной шайбы и значка.
    [1, 2, 3].forEach(function (н) {
      const ш = р.шайбы.find(function (э) { return э.область === н; });
      проверить(ш && ш.рисунок === 'шайбы-столиц' && ш.кадр === н - 1 && ш.размер === 32 && ш.значок && ш.значок.рисунок === 'значки' &&
        ш.значок.кадр === н - 1 && ш.значок.размер === 12, ключКарты + ': столица ' + н + ' — гранёная шайба со значком');
      if (ш && ш.значок) {
        const dx = ш.значок.x - ш.x;
        const dy = ш.значок.y - ш.y;
        проверить(dx > 0 && dy < 0 && Math.abs(Math.sqrt(dx * dx + dy * dy) - 16) < 1e-6,
          ключКарты + ': значок столицы ' + н + ' у верхнего правого края шайбы');
      }
    });
    const ничьяСтолица = р.шайбы.find(function (э) { return э.область === 7; });
    проверить(ничьяСтолица && ничьяСтолица.рисунок === 'шайбы' && ничьяСтолица.кадр === 6 && ничьяСтолица.столица === true &&
      ничьяСтолица.значок === null && ничьяСтолица.размер === 26, ключКарты + ': ничья столица — шайба дыма с отметкой');
    const обычная = р.шайбы.find(function (э) { return э.область === 4; });
    проверить(обычная && обычная.рисунок === 'шайбы' && обычная.кадр === 3 && обычная.значок === null && обычная.размер === 26,
      ключКарты + ': обычная шайба войск 26 px без значка');
    const сЗначками = Вид.собратьРаскладку(партия, { ширина: ШИРИНА, значкиНаВсех: true });
    const безЗначкаУНичьей = сЗначками.шайбы.filter(function (ш) { return ш.хозяин === null ? ш.значок === null : ш.значок !== null; }).length;
    проверить(безЗначкаУНичьей === сЗначками.шайбы.length, ключКарты + ': «значки на всех областях»: у хозяев есть, у ничьих нет');

    // Выбор и цели: внешние грани области, кадр = грань − 1.
    const выбранная = 5;
    const цели = [4, 10];
    const с = Вид.собратьРаскладку(партия, { ширина: ШИРИНА, выбрана: выбранная, цели: цели });
    function ожидаемыйКонтур(номера) {
      const итог = [];
      г.поле.forEach(function (строка, ряд) {
        строка.forEach(function (н, стб) {
          if (!номера.includes(н)) return;
          for (let грань = 1; грань <= 6; грань++) {
            if (г.сосед(ряд, стб, грань) !== н) итог.push({ ряд: ряд, стб: стб, грань: грань });
          }
        });
      });
      return итог;
    }
    const ожВыбор = ожидаемыйКонтур([выбранная]);
    const ожЦели = ожидаемыйКонтур(цели);
    проверить(ожВыбор.length >= 6, ключКарты + ': ожидаемых граней выбора ' + ожВыбор.length);
    проверить(ожЦели.length >= 6, ключКарты + ': ожидаемых граней целей ' + ожЦели.length);
    проверить(JSON.stringify(ключи(с.слои['выбор'], ['ряд', 'стб', 'грань'])) === JSON.stringify(ключи(ожВыбор, ['ряд', 'стб', 'грань'])),
      ключКарты + ': выбор ' + с.слои['выбор'].length + ' не совпал с ожидаемым ' + ожВыбор.length);
    проверить(JSON.stringify(ключи(с.слои['цели'], ['ряд', 'стб', 'грань'])) === JSON.stringify(ключи(ожЦели, ['ряд', 'стб', 'грань'])),
      ключКарты + ': цели ' + с.слои['цели'].length + ' не совпали с ожидаемыми ' + ожЦели.length);
    проверить(с.слои['выбор'].every(function (э) { return э.рисунок === 'выбор' && э.кадр === э.грань - 1 && э.источник.x === (э.грань - 1) * 288; }) &&
      с.слои['цели'].every(function (э) { return э.рисунок === 'цели' && э.кадр === э.грань - 1; }), ключКарты + ': кадры выбора и целей');
    // Без выбора и целей слоёв нет.
    проверить(р.слои['выбор'].length === 0 && р.слои['цели'].length === 0 && р.слои['стрелки'].length === 0, ключКарты + ': без выбора слои пусты');
    // Выбор и цели лежат выше границ краёв и ниже ничего лишнего.
    let посл = -1;
    let порядок2 = true;
    с.список.forEach(function (э) { const н = порядок.indexOf(э.слой); if (н < посл) порядок2 = false; посл = Math.max(посл, н); });
    проверить(порядок2, ключКарты + ': с выбором и целями порядок слоёв держится');

    // Лёгкий режим: тот же размер на экране, лист «-лёгкая», кадр 144×164; прочие листы — прежние.
    const л = Вид.собратьРаскладку(партия, { ширина: ШИРИНА, лёгкий: true, выбрана: выбранная });
    проверить(л.слои['тела'].length === тела.length && л.слои['тела'].every(function (э, и) {
      return /^сота-[а-я]+-лёгкая$/.test(э.рисунок) && э.источник.ширина === 144 && э.источник.высота === 164 &&
        э.куда.x === тела[и].куда.x && э.куда.ширина === тела[и].куда.ширина;
    }), ключКарты + ': лёгкие соты — лист «-лёгкая», кадр 144×164, место то же');
    проверить(л.слои['кромки'].length === р.слои['кромки'].length && л.слои['кромки'].every(function (э) {
      return э.источник.x === э.грань * 144 && э.источник.ширина === 144;
    }), ключКарты + ': лёгкие кромки — кадры по 144');
    проверить(л.слои['выбор'].length > 0 && л.слои['выбор'].every(function (э) { return э.источник.ширина === 288; }) &&
      л.слои['границы-краёв'].every(function (э) { return э.источник.ширина === 288; }), ключКарты + ': выбор и граница края в лёгком режиме те же файлы');

    // ---- Рисование: только разрешённое и только drawImage готовых картинок ----
    [false, true].forEach(function (легко) {
      const раскладка = Вид.собратьРаскладку(партия, { ширина: ШИРИНА, лёгкий: легко, выбрана: выбранная, цели: цели });
      const хол = поддельныйХолст();
      const картинки = поддельныеКартинки();
      const отчёт = Вид.нарисовать(хол.ctx, раскладка, картинки, { ширинаХолста: 358, высотаХолста: раскладка.геометрия.высота });
      const метка = ключКарты + (легко ? ' лёгкий' : ' полный') + ': ';
      const рисунки = хол.вызовы.filter(function (в) { return в.имя === 'drawImage'; });
      проверить(рисунки.length > 100, метка + 'вызовов drawImage ' + рисунки.length);
      проверить(рисунки.length === раскладка.список.length && отчёт.нарисовано === раскладка.список.length && отчёт.нет.length === 0,
        метка + 'drawImage ' + рисунки.length + ' на ' + раскладка.список.length + ' элементов списка');
      const лишниеВызовы = хол.вызовы.filter(function (в) { return !РАЗРЕШЁННЫЕ_ВЫЗОВЫ.includes(в.имя); }).map(function (в) { return в.имя; });
      проверить(лишниеВызовы.length === 0, метка + 'лишние вызовы холста: ' + лишниеВызовы.slice(0, 3).join(', '));
      const запрещённые = хол.вызовы.filter(function (в) { return ЗАПРЕЩЁННЫЕ_ВЫЗОВЫ.includes(в.имя); });
      проверить(запрещённые.length === 0, метка + 'запрещённые вызовы: ' + запрещённые.length);
      const лишниеСвойства = хол.присваивания.filter(function (п) { return !РАЗРЕШЁННЫЕ_СВОЙСТВА.includes(п.имя); }).map(function (п) { return п.имя; });
      проверить(лишниеСвойства.length === 0, метка + 'присвоены лишние свойства: ' + лишниеСвойства.slice(0, 3).join(', '));
      проверить(хол.присваивания.filter(function (п) { return ЗАПРЕЩЁННЫЕ_СВОЙСТВА.includes(п.имя); }).length === 0, метка + 'запрещённые свойства');
      // Порядок и числа каждого drawImage — как в списке.
      const сходится = рисунки.every(function (в, и) {
        const э = раскладка.список[и];
        const а = в.арг;
        return а.length === 9 && а[0] === картинки[э.рисунок] && а[1] === э.источник.x && а[2] === э.источник.y &&
          а[3] === э.источник.ширина && а[4] === э.источник.высота && а[5] === э.куда.x && а[6] === э.куда.y &&
          а[7] === э.куда.ширина && а[8] === э.куда.высота;
      });
      проверить(сходится, метка + 'каждый drawImage — как в списке и по порядку слоёв');
      проверить(хол.вызовы.filter(function (в) { return в.имя === 'save'; }).length === 1 &&
        хол.вызовы.filter(function (в) { return в.имя === 'restore'; }).length === 1, метка + 'save и restore парные');
    });

    // Нет картинок — ничего не рисуется (заглушек нет), холст только очищается.
    const пустой = поддельныйХолст();
    const отчётПустой = Вид.нарисовать(пустой.ctx, р, {}, {});
    проверить(отчётПустой.нарисовано === 0 && отчётПустой.нет.length > 5, ключКарты + ': без картинок нарисовано ' + отчётПустой.нарисовано);
    проверить(пустой.вызовы.every(function (в) { return ['save', 'restore', 'setTransform', 'clearRect'].includes(в.имя); }) &&
      пустой.присваивания.length === 0, ключКарты + ': без картинок на холст не уходит ничего, кроме очистки');
  });

  // ---- Наливание: прозрачность ставится и сразу возвращается; других свойств нет ----
  (function () {
    const партия = состояниеШестерых('остров');
    const р = Вид.собратьРаскладку(партия, { ширина: ШИРИНА });
    р.список.filter(function (э) { return э.слой === 'тела'; })[0].альфа = 0.5;
    const хол = поддельныйХолст();
    Вид.нарисовать(хол.ctx, р, поддельныеКартинки(), {});
    проверить(JSON.stringify(хол.присваивания.map(function (п) { return [п.имя, п.значение]; })) === JSON.stringify([['globalAlpha', 0.5], ['globalAlpha', 1]]),
      'наливание: globalAlpha 0,5 и сразу назад в 1 (получено ' + JSON.stringify(хол.присваивания) + ')');
    // Зум и сдвиг — через setTransform, перед очисткой стоит единичное преобразование.
    const хол2 = поддельныйХолст();
    Вид.нарисовать(хол2.ctx, р, поддельныеКартинки(), { зум: 2, сдвигX: 10, сдвигY: -5 });
    const преобразования = хол2.вызовы.filter(function (в) { return в.имя === 'setTransform'; }).map(function (в) { return в.арг.join(','); });
    проверить(преобразования.length === 2 && преобразования[0] === '1,0,0,1,0,0' && преобразования[1] === '2,0,0,2,10,-5',
      'зум и сдвиг через setTransform: ' + преобразования.join(' | '));
  })();

  // ---- Поле моря шире карты (при зуме): плитки покрывают его, без дыр ----
  (function () {
    const р = Вид.собратьРаскладку(состояниеШестерых('остров'), { ширина: ШИРИНА, поле: { x: -100, y: -50, ширина: 700, высота: 900 } });
    const площадь = р.слои['море'].reduce(function (а, э) { return а + э.куда.ширина * э.куда.высота; }, 0);
    проверить(Math.abs(площадь - 700 * 900) < 1e-3 && р.слои['море'].every(function (э) {
      return Math.abs(э.источник.ширина - 2 * э.куда.ширина) < 1e-6 && э.источник.x >= 0 && э.источник.x + э.источник.ширина <= 512 + 1e-6;
    }), 'море на большом поле: площадь ' + площадь);
  })();

  // ---- Настоящая партия из правил: цвет по месту, столицы ----
  (function () {
    const партия = Правила.новаяПартия({ игроки: ['а', 'б', 'в', 'г'], карта: 'материк' }, function () { return 0.5; });
    const р = Вид.собратьРаскладку(партия, { ширина: ШИРИНА });
    const гранёные = р.шайбы.filter(function (ш) { return ш.рисунок === 'шайбы-столиц'; });
    проверить(гранёные.length === 4, 'партия из правил на 4 места: гранёных шайб ' + гранёные.length);
    партия.игроки.forEach(function (ключ, место) {
      const столица = партия.столицы.find(function (с) { return с.хозяинНаСтарте === ключ; });
      const ш = р.шайбы.find(function (э) { return э.область === столица.область; });
      проверить(ш && ш.кадр === место && ш.значок && ш.значок.кадр === место, 'партия из правил: столица места ' + (место + 1) + ' в цвете места');
    });
    // Один из хозяев вышел: его области стали ничьими — их листы дымовые.
    const хозяин = партия.игроки[1];
    партия.хозяева = партия.хозяева.map(function (х) { return х === хозяин ? null : х; });
    const р2 = Вид.собратьРаскладку(партия, { ширина: ШИРИНА });
    проверить(р2.слои['тела'].some(function (э) { return э.рисунок === 'сота-дым'; }) &&
      !р2.слои['тела'].some(function (э) { return э.рисунок === 'сота-лазурь'; }),
      'партия из правил: сдавшийся стал дымом (лазури нет)');
    // Хозяин не из мест — ошибка, а не тихий дым.
    партия.хозяева[5] = 'чужой';
    let упало = false;
    try { Вид.собратьРаскладку(партия, { ширина: ШИРИНА }); } catch (е) { упало = true; }
    проверить(упало, 'хозяин без места за столом — ошибка');
    let безШирины = false;
    try { Вид.собратьРаскладку(партия, {}); } catch (е) { безШирины = true; }
    проверить(безШирины, 'без ширины карты — ошибка');
  })();

  // ---- Настоящие партии из правил: остров на 2 и 3 места, материк на 5 мест ----
  [['остров', 2], ['остров', 3], ['материк', 5]].forEach(function (набор) {
    const ключКарты = набор[0];
    const мест = набор[1];
    const метка = ключКарты + ' на ' + мест + ' места: ';
    const игроки = ['а', 'б', 'в', 'г', 'д'].slice(0, мест);
    const партия = Правила.новаяПартия({ игроки: игроки, карта: ключКарты }, function () { return 0.5; });
    const р = Вид.собратьРаскладку(партия, { ширина: ШИРИНА });
    const цветаМест = ['коралл', 'лазурь', 'янтарь', 'аметист', 'бирюза'];
    const карта = Карты.КАРТЫ[ключКарты];
    проверить(партия.игроки.length === мест && партия.столицы.length === мест, метка + 'партия собралась (столиц ' + партия.столицы.length + ')');
    проверить(р.шайбы.length === карта.области.length, метка + 'шайб ' + р.шайбы.length + ' из ' + карта.области.length);
    // Цвет листа каждого тела — по хозяину области (ничья — дым).
    const неТот = р.слои['тела'].filter(function (э) {
      const х = партия.хозяева[э.область];
      return э.рисунок !== 'сота-' + (х === null ? 'дым' : цветаМест[игроки.indexOf(х)]);
    });
    проверить(р.слои['тела'].length > 50 && неТот.length === 0, метка + 'тел с не тем цветом: ' + неТот.length);
    проверить(р.слои['тела'].some(function (э) { return э.рисунок === 'сота-дым'; }), метка + 'ничьи области есть и в дыму');
    // Столицы: гранёная шайба со значком в цвете места; её хозяин на карте — её кадр.
    игроки.forEach(function (ключ, место) {
      const столица = партия.столицы.find(function (с) { return с.хозяинНаСтарте === ключ; });
      const ш = столица && р.шайбы.find(function (э) { return э.область === столица.область; });
      проверить(ш && ш.рисунок === 'шайбы-столиц' && ш.кадр === место && ш.значок && ш.значок.кадр === место && ш.размер === 32,
        метка + 'столица места ' + (место + 1) + ' — гранёная шайба в его цвете');
    });
    проверить(р.шайбы.filter(function (ш) { return ш.рисунок === 'шайбы-столиц'; }).length === мест, метка + 'гранёных шайб ровно по числу мест');
    const обычные = р.шайбы.filter(function (ш) { return ш.рисунок === 'шайбы'; });
    проверить(обычные.length === карта.области.length - мест && обычные.every(function (ш) {
      return ш.значок === null && ш.размер === 26 && ш.кадр === (ш.хозяин === null ? 6 : игроки.indexOf(ш.хозяин));
    }), метка + 'обычные шайбы войск: кадр по хозяину, дым у ничьих');
  });

  // ---- Цели без повторов и без выбранной области ----
  (function () {
    const партия = состояниеШестерых('материк');
    const чистая = Вид.собратьРаскладку(партия, { ширина: ШИРИНА, выбрана: 5, цели: [4, 10] });
    const грязная = Вид.собратьРаскладку(партия, { ширина: ШИРИНА, выбрана: 5, цели: [4, 4, 10, 5, 10] });
    проверить(чистая.слои['цели'].length > 0 && грязная.слои['цели'].length === чистая.слои['цели'].length,
      'цели с повторами и выбранной: ' + грязная.слои['цели'].length + ' вместо ' + чистая.слои['цели'].length);
    проверить(грязная.слои['цели'].every(function (э) { return э.область !== 5; }), 'цель, совпавшая с выбранной, не рисуется как цель');
    проверить(грязная.слои['выбор'].length === чистая.слои['выбор'].length && грязная.слои['выбор'].length > 0, 'выбор рисуется один раз');
  })();

  // ---- Понятные ошибки при неполном входе ----
  (function () {
    const целая = состояниеШестерых('остров');
    function сОшибкой(партия, часть) {
      try { Вид.собратьРаскладку(партия, { ширина: ШИРИНА }); } catch (е) { return е instanceof Error && е.message.indexOf(часть) !== -1; }
      return false;
    }
    const безХозяев = Object.assign({}, целая); delete безХозяев.хозяева;
    const безИгроков = Object.assign({}, целая); delete безИгроков.игроки;
    const безКарты = Object.assign({}, целая, { карта: 'нет-такой' });
    проверить(сОшибкой(безХозяев, 'партия.хозяева'), 'нет партия.хозяева — понятная ошибка');
    проверить(сОшибкой(безИгроков, 'партия.игроки'), 'нет партия.игроки — понятная ошибка');
    проверить(сОшибкой(безКарты, 'Нет такой карты'), 'нет такой карты — понятная ошибка');
    проверить(сОшибкой(null, 'партия.хозяева'), 'партия не передана — понятная ошибка');
  })();

  // ---- Устройство файла: в коде нет запрещённых вызовов и присваиваний (комментарии не считаются) ----
  (function () {
    const текст = fs.readFileSync(путьВида, 'utf8');
    const код = текст.split('\n').map(function (с) { return с.replace(/\/\/.*$/, ''); }).join('\n');
    const вызов = new RegExp('\\.(' + ЗАПРЕЩЁННЫЕ_ВЫЗОВЫ.join('|') + ')\\s*\\(');
    const свойство = new RegExp('\\b(' + ЗАПРЕЩЁННЫЕ_СВОЙСТВА.join('|') + ')\\s*=[^=]');
    проверить(!вызов.test(код), 'в файле нет запрещённых вызовов холста' + (вызов.test(код) ? ': ' + код.match(вызов)[0] : ''));
    проверить(!свойство.test(код), 'в файле нет запрещённых присваиваний' + (свойство.test(код) ? ': ' + код.match(свойство)[0] : ''));
    проверить(/ctx\.drawImage\(/.test(код), 'в файле есть вызов drawImage (ноль найденного — провал)');
    проверить(!/document|setTimeout|Date\.now|Math\.random/.test(код), 'в файле нет document, таймеров, часов и случая');
  })();
}

