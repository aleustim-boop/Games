/** Разложить руки и колоду так, как просит раскладка. */
function расставить(игра, раскладка) {
  const сколькоИгроков = раскладка.руки.length;
  const партия = игра.создатьПартию({ игроков: сколькоИгроков, зерно: 20250910 });

  // Все карты в одну кучу, а потом раздаём столько, сколько просят.
  const запас = [];
  for (const имя of партия.игроки) запас.push(...партия.руки[имя]);
  запас.push(...партия.колода);

  let взято = 0;
  партия.игроки.forEach(function (имя, где) {
    партия.руки[имя] = запас.slice(взято, взято + раскладка.руки[где]);
    взято += раскладка.руки[где];
  });
  партия.колода = запас.slice(взято, взято + раскладка.колода);

  // Стол пуст: подход только что закончился отбоем, карты уже уехали.
  партия.стол = [];
  партия.берёт = false;
  партия.пасы = [];
  партия.местоАтаки = 0;
  партия.атакует = партия.игроки[0];
  return партия;
}

/** Прогнать одну раскладку и вернуть список бед (пустой — всё сошлось). */
function проверитьРаскладку(игра, раскладка) {
  const беды = [];
  const партия = расставить(игра, раскладка);

  const очередь = игра.порядокДобора(партия);
  if (очередь.length !== раскладка.руки.length) {
    беды.push('в очереди добора ' + очередь.length + ' игроков, а за столом ' +
      раскладка.руки.length + ' — раскладка собралась не так, как задумано');
    return беды;
  }

  const былоНаРуках = {};
  for (const имя of партия.игроки) былоНаРуках[имя] = партия.руки[имя].length;
  const былоВКолоде = партия.колода.length;

  игра.завершитьПодход(партия);

  очередь.forEach(function (имя, место) {
    const добрал = партия.руки[имя].length - былоНаРуках[имя];
    if (добрал !== раскладка.добор[место]) {
      беды.push((место + 1) + '-й в очереди добора («' + имя + '») добрал ' + добрал +
        ' карт, а должен был ' + раскладка.добор[место]);
    }
    if (партия.руки[имя].length !== раскладка.руками[место]) {
      беды.push('у ' + (место + 1) + '-го в очереди («' + имя + '») на руках стало ' +
        партия.руки[имя].length + ' карт, а должно быть ' + раскладка.руками[место]);
    }
  });

  const роздано = раскладка.добор.reduce(function (сумма, сколько) { return сумма + сколько; }, 0);
  if (партия.колода.length !== былоВКолоде - роздано) {
    беды.push('в колоде осталось ' + партия.колода.length + ' карт, а должно ' +
      (былоВКолоде - роздано));
  }

  /* Отдельно — то, ради чего владелец и просил дележ: никто не должен
     вылететь из партии, пока в колоде были карты на всех. */
  const выбывшиеЗря = (партия.выбывшие || []).filter(function (имя) {
    const место = очередь.indexOf(имя);
    return место !== -1 && раскладка.руками[место] > 0;
  });
  if (выбывшиеЗря.length) {
    беды.push('из партии вышли «' + выбывшиеЗря.join(', ') + '», хотя по правилам ' +
      'карты им доставались — уходить было не с чего');
  }
  return беды;
}

/** Прогнать все раскладки. Отвечает списком бед по каждой. */
function прогнать(игра, показывать) {
  let провалов = 0;
  for (const раскладка of РАСКЛАДКИ) {
    let беды = [];
    try {
      беды = проверитьРаскладку(игра, раскладка);
    } catch (сбой) {
      беды = ['раскладка упала: ' + (сбой && сбой.message ? сбой.message : сбой)];
    }
    провалов += беды.length;
    if (показывать) {
      console.log((беды.length ? '  ПЛОХО — ' : '  ок    — ') + раскладка.имя +
        ' → ' + раскладка.словами);
      for (const беда of беды) console.log('           ' + беда);
    }
  }
  return провалов;
}

