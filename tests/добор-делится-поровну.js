/* =====================================================================
   ОСТАТОК КОЛОДЫ ДЕЛИТСЯ ПОРОВНУ — проверка ровно на случай владельца.

   Владелец написал так: «у меня 2 карты и у соперника 2, а в колоде 4,
   поделите поровну». Раньше игра давала первому по очереди полные шесть,
   а второму — что осталось: выходило 6 и 2. Теперь карты идут ПО ОДНОЙ
   ПО КРУГУ, и выходит 4 и 4.

   Почему эта проверка написана отдельно и числами. Большой прогон
   (tests/автопрогон-правил-компанией.js) сторожит СВОЙСТВА дележа —
   «никто не получил на две карты больше нуждающегося», «в колоде
   осталось только тогда, когда всем хватило». Свойства не устаревают,
   но и не говорят, сколько именно карт получит человек. А владелец
   просил не свойство, а число: по 4 и по 4. Числа здесь и записаны —
   руками, по словам правила, для шести раскладок.

   Раскладки строятся не случайно: руки и колода расставляются прямо,
   после чего зовётся дверь самой игры «завершитьПодход» — та же, что
   работает в настоящей партии.

   Порядок очереди спрашиваем у игры («порядокДобора») нарочно: под
   проверкой стоит ДЕЛЁЖ, а не круг, и второй копии круга нам заводить
   незачем — на копиях круга в этом проекте уже обжигались.

   Проверка умеет краснеть, и это доказывается тут же, вторым заходом:
   те же раскладки прогоняются по копии игры со СТАРЫМ правилом добора
   (tests/копия-игры-со-старым-добором.js). Если старое правило проходит
   проверку — виновата проверка, и стенд об этом скажет.

   Запуск:
       node tests/добор-делится-поровну.js
   ===================================================================== */

