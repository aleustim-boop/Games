'use strict';

/* =====================================================================
   ОФОРМЛЕНИЕ И ВИДИМОСТЬ — проверка двери window.Оформление.

   Что проверяем (без браузера, на поддельном браузере и поддельном
   облаке из tests/поддельный-браузер.js):

     1. выбор ставит признак на <html> (data-фон, data-рубашка,
        data-доска), пустое значение — снимает;
     2. незнакомая часть и мусор вместо названия не ломают страницу:
        дверь отвечает «нет», признак остаётся прежним;
     3. выбор переживает перезагрузку страницы (память телефона);
     4. выбор переезжает на второе устройство через облако, и побеждает
        СВЕЖИЙ: старая запись в облаке не отменяет нового выбора;
     5. вне Telegram всё работает на памяти телефона, консоль чиста;
     6. признак data-страница="скрыта" появляется, когда игру свернули,
        и снимается при возврате — и по событию браузера, и по событиям
        самого Telegram («deactivated»/«activated»);
     7. ключ хранения — латиницей, иначе облако его отвергнет;
     8. пустой слой фона стоит первым узлом внутри #приложение
        на index.html и шахматы.html.

   Запуск:  node tests/оформление-и-видимость.js
   Ответ:   «всё хорошо» и код 0, либо список бед и код 1.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const {
  КОРЕНЬ, поднятьTelegramJS, сделатьПамять, сделатьОблако, сделатьДокумент, поддельныеЧасы
} = require('./поддельный-браузер.js');

const беды = [];
function надо(условие, что) {
  if (!условие) беды.push(что);
}

/** Подождать, пока разойдутся обещания (облако отвечает не сразу). */
function передышка() {
  return new Promise(function (готово) { setTimeout(готово, 5); });
}

/** Поднять js/telegram.js как внутри Telegram: с облаком и часами. */
function поднять(настройки) {
  const н = настройки || {};
  const стенд = поднятьTelegramJS({
    память: н.память || сделатьПамять(false),
    документ: н.документ || сделатьДокумент(),
    часы: н.часы || поддельныеЧасы(),
    облако: н.облако,
    telegram: Object.assign({
      version: '8.0',
      isVersionAtLeast: function () { return true; }
    }, н.telegram || {})
  });
  стенд.дверь = стенд.окно.Оформление;
  стенд.корень = стенд.документ.documentElement;
  return стенд;
}

/** Что стоит на <html> в этом признаке. */
function признак(стенд, имя) {
  return стенд.корень.getAttribute(имя);
}

async function проверить() {
  // -------------------------------------------------------------------------
  // 1. Выбор ставит признак, пустое значение — снимает
  // -------------------------------------------------------------------------
  {
    const с = поднять({});
    надо(typeof с.дверь === 'object' && с.дверь !== null, 'дверь window.Оформление должна быть');
    надо(признак(с, 'data-фон') === null, 'пока ничего не выбрано, признака фона быть не должно');

    надо(с.дверь.поставить('фон', 'дыхание') === true, 'выбор фона должен приниматься');
    надо(признак(с, 'data-фон') === 'дыхание', 'признак data-фон должен стать «дыхание»');
    надо(с.дверь.какое('фон') === 'дыхание', 'дверь должна помнить выбранный фон');

    с.дверь.поставить('рубашка', 'бордо');
    с.дверь.поставить('доска', 'дерево');
    надо(признак(с, 'data-рубашка') === 'бордо', 'признак data-рубашка должен стать «бордо»');
    надо(признак(с, 'data-доска') === 'дерево', 'признак data-доска должен стать «дерево»');

    const всё = с.дверь.всё();
    надо(всё.фон === 'дыхание' && всё.рубашка === 'бордо' && всё.доска === 'дерево',
      'всё() должно вернуть три выбора, а вернуло: ' + JSON.stringify(всё));

    надо(с.дверь.поставить('фон', '') === true, 'пустое значение — это «как по умолчанию», его принимаем');
    надо(признак(с, 'data-фон') === null, 'пустое значение должно снимать признак');
    надо(с.дверь.какое('фон') === '', 'после снятия дверь должна отвечать пустой строкой');
    надо(признак(с, 'data-рубашка') === 'бордо', 'снятие фона не должно трогать рубашку');
  }

  // -------------------------------------------------------------------------
  // 2. Незнакомая часть и мусор не ломают страницу
  // -------------------------------------------------------------------------
  {
    const с = поднять({});
    с.дверь.поставить('фон', 'сукно');

    надо(с.дверь.поставить('потолок', 'сукно') === false, 'незнакомая часть должна получить «нет»');
    надо(с.дверь.какое('потолок') === '', 'у незнакомой части ничего не выбрано');
    надо(с.дверь.поставить('фон', 'а"><script>') === false, 'мусор вместо названия принимать нельзя');
    надо(с.дверь.поставить('фон', 'слишком-длинное-название-вида-которое-не-влезает') === false,
      'слишком длинное название принимать нельзя');
    надо(с.дверь.поставить('фон', { вид: 'сукно' }) === false, 'не-строку принимать нельзя');
    надо(признак(с, 'data-фон') === 'сукно', 'после отказов на странице должен остаться прежний вид');
    надо(с.ошибкиКонсоли.length === 0, 'красных строк в консоли быть не должно: ' + с.ошибкиКонсоли.join(' | '));
    надо(с.предупреждения.length > 0, 'разработчику стоит подсказать про незнакомую часть и мусор');
  }

  // -------------------------------------------------------------------------
  // 3. Выбор переживает перезагрузку страницы
  // -------------------------------------------------------------------------
  {
    const память = сделатьПамять(false);
    const первый = поднять({ память: память });
    первый.дверь.поставить('рубашка', 'бордо');

    const второй = поднять({ память: память });   // та же память, страница поднята заново
    надо(второй.дверь.какое('рубашка') === 'бордо', 'после перезагрузки выбор должен остаться');
    надо(признак(второй, 'data-рубашка') === 'бордо', 'после перезагрузки признак должен встать сразу');
  }

  // -------------------------------------------------------------------------
  // 4. Переезд на второе устройство: побеждает свежий выбор
  // -------------------------------------------------------------------------
  {
    // Первый телефон: выбрали фон, он уехал в облако
    const облако = сделатьОблако({});
    const первый = поднять({ облако: облако });
    await передышка();
    первый.дверь.поставить('фон', 'дыхание');
    await передышка();

    // Второй телефон: своя память, то же облако — выбор должен приехать
    const второй = поднять({ облако: облако });
    надо(второй.дверь.какое('фон') === '', 'до ответа облака на новом устройстве выбора ещё нет');
    await передышка();
    надо(второй.дверь.какое('фон') === 'дыхание', 'выбор должен приехать из облака');
    надо(признак(второй, 'data-фон') === 'дыхание', 'приехавший выбор должен встать на страницу');

    // А теперь на втором устройстве выбрали своё — старое облачное значение
    // не должно возвращать прежний вид при следующем открытии игры
    второй.дверь.поставить('фон', 'сукно');
    await передышка();
    const третий = поднять({ облако: облако, память: второй.память });
    await передышка();
    надо(третий.дверь.какое('фон') === 'сукно', 'побеждать должен свежий выбор, а вышло: ' + третий.дверь.какое('фон'));
  }

  // -------------------------------------------------------------------------
  // 5. Вне Telegram — память телефона, и ничего не падает
  // -------------------------------------------------------------------------
  {
    const память = сделатьПамять(false);
    const стенд = поднятьTelegramJS({ память: память });   // окна Telegram нет вовсе
    const дверь = стенд.окно.Оформление;
    let упало = null;
    try {
      дверь.поставить('фон', 'сукно');
      await дверь.загрузить();
    } catch (ошибка) {
      упало = ошибка;
    }
    надо(упало === null, 'вне Telegram оформление не должно падать, а оно бросило: ' + упало);
    надо(дверь.какое('фон') === 'сукно', 'вне Telegram выбор должен работать на памяти телефона');
    надо(стенд.документ.documentElement.getAttribute('data-фон') === 'сукно',
      'вне Telegram признак тоже должен ставиться');
    надо(стенд.ошибкиКонсоли.length === 0, 'вне Telegram красных строк быть не должно: ' + стенд.ошибкиКонсоли.join(' | '));
    надо(стенд.предупреждения.length === 0, 'вне Telegram консоль должна молчать: ' + стенд.предупреждения.join(' | '));

    const снова = поднятьTelegramJS({ память: память });
    надо(снова.окно.Оформление.какое('фон') === 'сукно', 'вне Telegram выбор должен пережить перезагрузку');
  }

  // -------------------------------------------------------------------------
  // 6. Признак «страница скрыта»
  // -------------------------------------------------------------------------
  {
    // По-браузерному: свернули вкладку
    const документ = сделатьДокумент();
    const с = поднять({ документ: документ });
    надо(признак(с, 'data-страница') === null, 'открытая игра не должна быть помечена скрытой');

    документ.hidden = true;
    документ.visibilityState = 'hidden';
    документ.dispatchEvent('visibilitychange');
    надо(признак(с, 'data-страница') === 'скрыта', 'свёрнутая игра должна получить data-страница="скрыта"');
    надо(с.дверь.страницаСкрыта() === true, 'дверь должна отвечать, что страница скрыта');

    документ.hidden = false;
    документ.visibilityState = 'visible';
    документ.dispatchEvent('visibilitychange');
    надо(признак(с, 'data-страница') === null, 'при возврате признак должен сниматься');
    надо(с.дверь.страницаСкрыта() === false, 'дверь должна отвечать, что страница видна');
  }

  {
    // По-телеграмному: Telegram не вкладка, у него свои события
    const события = {};
    const т = поднять({
      telegram: {
        onEvent: function (имя, дело) { (события[имя] = события[имя] || []).push(дело); },
        offEvent: function () {}
      }
    });
    надо(Array.isArray(события.deactivated) && события.deactivated.length === 1,
      'игра должна слушать telegram-событие «свернули»');
    надо(Array.isArray(события.activated) && события.activated.length === 1,
      'игра должна слушать telegram-событие «вернули»');

    события.deactivated[0]();
    надо(признак(т, 'data-страница') === 'скрыта', 'свёрнутый Telegram — тоже скрытая страница');
    события.activated[0]();
    надо(признак(т, 'data-страница') === null, 'вернулись в Telegram — признак снимается');
  }

  // -------------------------------------------------------------------------
  // 7. Ключ хранения — латиницей (иначе облако его отвергает)
  // -------------------------------------------------------------------------
  {
    const облако = сделатьОблако({});
    const с = поднять({ облако: облако });
    с.дверь.поставить('доска', 'дерево');
    await передышка();

    const ключиПамяти = с.память.ключи();
    надо(ключиПамяти.indexOf('skins') !== -1,
      'выбор должен лечь под латинский ключ «skins», а легли: ' + ключиПамяти.join(','));
    for (const ключ of ключиПамяти) {
      надо(/^[A-Za-z0-9_-]+$/.test(ключ), 'ключ «' + ключ + '» не латинский — облако такой отвергнет');
    }
    const вОблаке = Object.keys(облако.ящик || {});
    надо(вОблаке.indexOf('skins') !== -1,
      'выбор должен доехать до облака под ключом «skins», а там: ' + вОблаке.join(','));
  }

  // -------------------------------------------------------------------------
  // 8. Слой фона стоит первым узлом внутри #приложение
  // -------------------------------------------------------------------------
  {
    for (const страница of ['index.html', 'шахматы.html']) {
      const текст = fs.readFileSync(path.join(КОРЕНЬ, страница), 'utf8');
      const место = текст.indexOf('<div id="приложение">');
      надо(место !== -1, страница + ': не нашёл #приложение');
      const хвост = текст.slice(место);
      надо(/<div class="фон-игры" aria-hidden="true"><\/div>/.test(хвост),
        страница + ': нет пустого слоя фона <div class="фон-игры" aria-hidden="true"></div>');
      const доСлоя = хвост.slice(0, хвост.indexOf('<div class="фон-игры"'));
      надо(!/<section|<main|<header|<button/i.test(доСлоя),
        страница + ': слой фона должен идти первым узлом внутри #приложение');
    }
  }

  // -------------------------------------------------------------------------
  // Итог
  // -------------------------------------------------------------------------
  if (беды.length) {
    console.log('ПЛОХО, бед ' + беды.length + ':');
    for (const беда of беды) console.log('  — ' + беда);
    process.exit(1);
  }
  console.log('оформление и видимость: всё хорошо — признаки ставятся, выбор переезжает через облако, скрытая страница помечается');
  process.exit(0);
}

проверить().catch(function (ошибка) {
  console.log('ПЛОХО: проверка сама сломалась — ' + (ошибка && ошибка.stack || ошибка));
  process.exit(1);
});
