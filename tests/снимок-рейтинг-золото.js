function экранироватьRegExp(текст) {
  return текст.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/** Значение CSS-переменной ровно так, как оно записано в файле — без
 *  второй, вручную вписанной копии числа внутри этой проверки. */
function читатьПеременную(текстCSS, имя) {
  const рег = new RegExp(экранироватьRegExp(имя) + ':\\s*([^;]+);');
  const совпадение = текстCSS.match(рег);
  if (!совпадение) {
    throw new Error('в style.css не нашлась переменная «' + имя + '» — приём объявления поменялся, обновите эту проверку');
  }
  return совпадение[1].trim();
}

function свободныйПорт() {
  return new Promise((готово, брак) => {
    const проба = http.createServer();
    проба.on('error', брак);
    проба.listen(0, АДРЕС_ХОЗЯИНА, () => {
      const порт = проба.address().port;
      проба.close(() => готово(порт));
    });
  });
}

async function выбратьСвободныйПорт() {
  for (let попытка = 0; попытка < 6; попытка++) {
    const порт = await свободныйПорт();
    if (ЗАПРЕЩЁННЫЕ_ПОРТЫ.indexOf(порт) === -1) return порт;
  }
  throw new Error('не удалось получить свободный порт, отличный от боевых 8790/8791');
}

