'use strict';

/* =====================================================================
   ПРОГОН ВСЕХ УЗЛОВ — ищет в tests/ проверки, которые сейчас молча красные.

   Зачем. В tests/ лежат сотни отдельных проверок. Каждую по одной ещё
   можно запускать руками, а вот заметить, что какая-то из них давно
   не запускается и тихо ломается — почти невозможно: никто не бежит
   по всей папке разом. Этот файл бежит по всей папке разом и говорит,
   что покраснело.

   Что он делает:
     1. Смотрит на каждый tests/*.js.
     2. Браузерные проверки (нужен настоящий Chromium через playwright)
        не трогает — они дорогие, для них есть отдельный ручной прогон.
        Браузерность узнаём по тексту файла: require('playwright'),
        слово chromium или требование './браузер-робот.js'.
     3. Служебные помощники — не проверки, а инструменты (локальный
        сервер для ручного открытия игры, поддельный Telegram-сервер,
        медленный посредник, стенды для ручного разглядывания рейтинга)
        — тоже не трогает. У них общая примета: внутри есть server.listen(),
        а server.close() — нет нигде, то есть сервер поднимается и висит
        вечно, ожидая, что человек откроет браузер сам. Гонять такой файл
        через таймаут — только жечь 120 секунд без всякого толка.
     4. Проверки, которые по умолчанию (без своего порта в доводе) стучат
        на боевой порт 8790, тоже не трогает — 8790 это комната боевого
        сервера, её трогать нельзя (см. CLAUDE.md).
     5. Всё, что осталось, запускает по одной — новым процессом node,
        с рабочей папкой в корне проекта и потолком в 120 секунд на файл.
        0 на выходе — зелёная. Ненулевой код разбираем ещё раз по тому,
        что файл САМ напечатал (это уже не текст файла заранее, а вывод
        после запуска):
          - «ReferenceError: window/document is not defined» — не проверка,
            а помощник для вставки в консоль браузера, в node ему не место;
          - фраза вида «требуется явно указать…», «скажите…», «не сказал(и)…»,
            «укажите…» — файл честно попросил довод командной строки, которого
            мы ему не дали;
          - «ECONNREFUSED» — файл стучится на сервер, который должен был
            поднять кто-то другой (не этот прогон).
        Эти три случая не провал проверки — они складываются в свои кучки
        и в счёт красных не идут. Настоящий провал — всё, что осталось
        (для неё в отчёт идут последние 15 строк её собственного вывода).

   В конце — одна строка-итог, имена всех красных с местом на диске
   и списком по каждой пропущенной кучке.

   Запуск:
       node tests/прогон-всех-узлов.js
       node tests/прогон-всех-узлов.js --папка=D:\путь\к\копии   (для ломающего запуска —
           смотрит *.js не в tests/, а в указанной папке; сам файл в этом
           списке не участвует, поэтому ломающая копия не обязана как-то
           называться иначе)

   Ломающий запуск (проверка себя):
       положить во временную папку один файл вида «process.exit(1)»
       и позвать node tests/прогон-всех-узлов.js --папка=<та папка> —
       программа обязана посчитать его красным и завершиться кодом 1.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const КОРЕНЬ = path.resolve(path.join(__dirname, '..'));
const ИМЯ_ЭТОГО_ФАЙЛА = path.basename(__filename);
const ТАЙМАУТ_МС = 120000;
const СТРОК_В_ХВОСТЕ = 15;

function довод(имя) {
  const найден = process.argv.find(function (а) { return а.indexOf(имя + '=') === 0; });
  return найден ? найден.slice(имя.length + 1) : null;
}

const ПАПКА = довод('--папка') ? path.resolve(довод('--папка')) : __dirname;

// Требует настоящий браузер (playwright/Chromium) — гоняем отдельно, руками.
const ПАТТЕРН_БРАУЗЕРА = /require\(\s*['"]playwright['"]\s*\)|chromium|браузер-робот/i;
// Стучит по умолчанию на боевую комнату 8790 — трогать нельзя.
const ПАТТЕРН_ПОРТА_8790 = /\|\|\s*'?8790'?|\.listen\([^)]*8790|:8790'\)/;

// Эти три признака узнаём не по тексту файла заранее, а по тому, что он
// сам напечатал после запуска — файл не проверка правил, а либо помощник
// для вставки в браузер (никакой playwright/chromium в тексте нет, но внутри
// используются window/document — в node их просто не существует), либо
// честно требует свой довод командной строки, либо стучится на сервер,
// который должен был поднять кто-то другой.
const ПАТТЕРН_БРАУЗЕРНОГО_ВЫВОДА = /ReferenceError:\s*(window|document)\s+is not defined/i;
const ПАТТЕРН_ДОВОДА_В_ВЫВОДЕ = /требуется явно указать|скажите|не сказал|нужно указать|укажите|не хватает довод|нужен довод/i;
const ПАТТЕРН_ЧУЖОГО_СЕРВЕРА = /ECONNREFUSED/;

/** браузерный-помощник | нужен-довод | нужен-чужой-сервер | null (настоящий провал) */
function причинаПровалаПоВыводу(вывод) {
  const текст = String(вывод || '');
  if (ПАТТЕРН_БРАУЗЕРНОГО_ВЫВОДА.test(текст)) return 'браузерный-помощник';
  if (ПАТТЕРН_ЧУЖОГО_СЕРВЕРА.test(текст)) return 'нужен-чужой-сервер';
  if (ПАТТЕРН_ДОВОДА_В_ВЫВОДЕ.test(текст)) return 'нужен-довод';
  return null;
}

function списокФайлов() {
  return fs.readdirSync(ПАПКА)
    .filter(function (имя) { return имя.endsWith('.js'); })
    .filter(function (имя) { return имя !== ИМЯ_ЭТОГО_ФАЙЛА; })
    .sort();
}

/** браузерная | служебная | порт-8790 | обычная */
function классифицировать(текст) {
  if (ПАТТЕРН_БРАУЗЕРА.test(текст)) return 'браузерная';
  const виситСервер = /\.listen\(/.test(текст) && !/\.close\(/.test(текст);
  if (виситСервер) return 'служебная';
  if (ПАТТЕРН_ПОРТА_8790.test(текст)) return 'порт-8790';
  return 'обычная';
}

function хвост(текст, сколькоСтрок) {
  const строки = String(текст || '').replace(/\r\n/g, '\n').split('\n');
  while (строки.length && строки[строки.length - 1] === '') строки.pop();
  return строки.slice(-сколькоСтрок).join('\n');
}

function запуститьОдин(имяФайла) {
  const путь = path.join(ПАПКА, имяФайла);
  const старт = Date.now();
  const р = spawnSync(process.execPath, [путь], {
    cwd: КОРЕНЬ,
    timeout: ТАЙМАУТ_МС,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024
  });
  const времяМс = Date.now() - старт;
  const этоТаймаут = (р.error && р.error.code === 'ETIMEDOUT') ||
    (р.status === null && времяМс >= ТАЙМАУТ_МС - 1000);
  return {
    имяФайла: имяФайла,
    путь: путь,
    код: р.status,
    сигнал: р.signal,
    времяМс: времяМс,
    таймаут: этоТаймаут,
    вывод: хвост((р.stdout || '') + (р.stderr || ''), СТРОК_В_ХВОСТЕ),
    ошибкаЗапуска: р.error && !этоТаймаут ? String(р.error.message || р.error) : null
  };
}

function главная() {
  console.log('Прогон всех узлов — папка: ' + ПАПКА);
  console.log('');

  const все = списокФайлов();
  const браузерные = [];
  const служебные = [];
  const порт8790 = [];
  const обычные = [];

  for (const имя of все) {
    const текст = fs.readFileSync(path.join(ПАПКА, имя), 'utf8');
    const вид = классифицировать(текст);
    if (вид === 'браузерная') браузерные.push(имя);
    else if (вид === 'служебная') служебные.push(имя);
    else if (вид === 'порт-8790') порт8790.push(имя);
    else обычные.push(имя);
  }

  console.log('Пропущено браузерных (' + браузерные.length + '): ' + (браузерные.join(', ') || '—'));
  console.log('');
  console.log('Пропущено служебных, без итоговой строки (' + служебные.length + '): ' + (служебные.join(', ') || '—'));
  console.log('');
  console.log('Пропущено — по умолчанию стучат на боевой порт 8790 (' + порт8790.length + '): ' + (порт8790.join(', ') || '—'));
  console.log('');
  console.log('К запуску: ' + обычные.length + ' файлов');
  console.log('');

  const зелёные = [];
  const красные = [];
  const тайм = [];
  const браузерныеПоВыводу = [];
  const нужноДоводом = [];
  const нужноЧужимСервером = [];

  for (const имя of обычные) {
    process.stdout.write('… ' + имя + ' ');
    const итог = запуститьОдин(имя);
    if (итог.таймаут) {
      тайм.push(итог);
      console.log('— ТАЙМ-АУТ (>' + Math.round(ТАЙМАУТ_МС / 1000) + ' с)');
      continue;
    }
    if (итог.код === 0) {
      зелёные.push(итог);
      console.log('— зелёная (' + итог.времяМс + ' мс)');
      continue;
    }

    // Код не 0 — но это ещё не значит «настоящий провал»: файл мог быть
    // помощником для браузерной консоли, требовать свой довод командной
    // строки или ждать сервер, который поднимает другой процесс.
    const причина = причинаПровалаПоВыводу(итог.вывод);
    if (причина === 'браузерный-помощник') {
      браузерныеПоВыводу.push(итог);
      console.log('— пропущена: браузерный помощник (в выводе window/document is not defined)');
      continue;
    }
    if (причина === 'нужен-довод') {
      нужноДоводом.push(итог);
      console.log('— пропущена: требует свой довод командной строки (по выводу)');
      continue;
    }
    if (причина === 'нужен-чужой-сервер') {
      нужноЧужимСервером.push(итог);
      console.log('— пропущена: ждёт сервер, который поднимает другой процесс (ECONNREFUSED)');
      continue;
    }

    красные.push(итог);
    console.log('— КРАСНАЯ (код ' + итог.код + (итог.сигнал ? ', сигнал ' + итог.сигнал : '') + ', ' + итог.времяМс + ' мс)');
    if (итог.ошибкаЗапуска) console.log('   не удалось запустить: ' + итог.ошибкаЗапуска);
    if (итог.вывод) {
      console.log('   последние строки вывода:');
      for (const строка of итог.вывод.split('\n')) console.log('   | ' + строка);
    }
  }

  console.log('');
  console.log('===================================================================');
  console.log('Итого: зелёных ' + зелёные.length + ', красных ' + красные.length +
    ', тайм-аутов ' + тайм.length +
    ', пропущено браузерных (по тексту файла) ' + браузерные.length +
    ', пропущено служебных ' + служебные.length +
    ', пропущено (порт 8790) ' + порт8790.length +
    ', пропущено — браузерный помощник (по выводу) ' + браузерныеПоВыводу.length +
    ', пропущено — нужен свой довод ' + нужноДоводом.length +
    ', пропущено — нужен чужой сервер ' + нужноЧужимСервером.length);
  if (красные.length) console.log('Красные: ' + красные.map(function (и) { return и.имяФайла; }).join(', '));
  if (тайм.length) console.log('Тайм-ауты: ' + тайм.map(function (и) { return и.имяФайла; }).join(', '));
  if (браузерныеПоВыводу.length) console.log('Браузерный помощник (по выводу): ' + браузерныеПоВыводу.map(function (и) { return и.имяФайла; }).join(', '));
  if (нужноДоводом.length) console.log('Нужен свой довод: ' + нужноДоводом.map(function (и) { return и.имяФайла; }).join(', '));
  if (нужноЧужимСервером.length) console.log('Нужен чужой сервер: ' + нужноЧужимСервером.map(function (и) { return и.имяФайла; }).join(', '));

  process.exit((красные.length || тайм.length) ? 1 : 0);
}

главная();
