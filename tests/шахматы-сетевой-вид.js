/** Экран шахмат в песочнице: свежий DOM, настоящие правила, поддельные
 *  лист «⋯», рекорды и связь window.Сеть (она запоминает просьбы). */
function собратьЭкран() {
  const document = создатьDocument();
  построитьРазметку(document);
  // Кнопки выбора фигуры в плашке превращения — как в шахматы.html.
  const плашка = document.getElementById('экран-превращения');
  ['ферзь', 'ладья', 'слон', 'конь'].forEach(function (тип) {
    const кнопка = document.createElement('button');
    кнопка.classList.add('кнопка--превращение');
    кнопка.setAttribute('data-фигура', тип);
    плашка.appendChild(кнопка);
  });

  const просьбыСети = [];
  const window = {
    document: document,
    localStorage: (function () {
      const память = new Map();
      return {
        getItem: function (k) { return память.has(k) ? память.get(k) : null; },
        setItem: function (k, v) { память.set(k, String(v)); }
      };
    })(),
    location: { href: '', search: '' },
    ШахматыПравила: require(путьКПравилам),
    ШахматыРекорды: { открыты: function () { return false; }, показать: function () {}, спрятать: function () {} },
    ЛистЕщё: {
      подключить: function () {
        return {
          открыть: function () {}, закрыть: function () {}, открыт: function () { return false; },
          освежитьКнопкуНастроек: function () {}, спроситьЗавершить: function () { return false; }
        };
      }
    },
    Сеть: {
      отправитьХод: function (письмо) { просьбыСети.push(письмо); return Promise.resolve({ принято: true }); }
    }
  };
  window.window = window;
  window.addEventListener = function () {};

  const песочница = {
    window: window, document: document, console: console,
    setTimeout: setTimeout, clearTimeout: clearTimeout,
    setInterval: setInterval, clearInterval: clearInterval,
    URLSearchParams: URLSearchParams
  };
  vm.createContext(песочница);
  vm.runInContext(fs.readFileSync(путьКФайлу, 'utf8'), песочница, { filename: путьКФайлу + ' (в памяти)' });

  const письма = [];
  const экран = window.ШахматыЭкран;
  if (экран) {
    экран.включитьСеть(function (письмо) {
      письма.push(JSON.parse(JSON.stringify(письмо)));
      return Promise.resolve({ принято: true });
    });
  }
  return { document: document, window: window, экран: экран, письма: письма, просьбыСети: просьбыСети };
}

/** Вид от сервера — так же, как его собирает server/игры/шахматы.js. */
function видИзFEN(fen, мойЦвет, добавка) {
  const партия = Правила.партияИзFEN(fen);
  const вид = {
    fen: fen,
    доска: Правила.картинкаПартии(партия),
    чейХод: Правила.чейХод(партия),
    мойЦвет: мойЦвет,
    яХожу: Правила.чейХод(партия) === мойЦвет,
    шах: Правила.подШахом(партия),
    завершена: false,
    номерСобытия: 1,
    можноПредложитьНичью: true
  };
  return Object.assign(вид, добавка || {});
}

function клетка(э, поле) {
  const узелДоски = э.document.getElementById('доска');
  return узелДоски.children.find(function (к) { return к.getAttribute('data-поле') === поле; }) || null;
}

function тап(э, поле) {
  const к = клетка(э, поле);
  if (к) э.document.getElementById('доска')._emit('click', { target: к });
  return Boolean(к);
}

/** Какая фигура стоит в клетке: «белая король» или '' для пустой. */
function фигураВКлетке(э, поле) {
  const к = клетка(э, поле);
  if (!к) return null;
  const знак = найтиПоКлассу(к, 'фигура');
  if (!знак) return '';
  const классы = знак.className.split(' ');
  const цвет = классы.indexOf('фигура--белая') !== -1 ? 'белая' : классы.indexOf('фигура--чёрная') !== -1 ? 'чёрная' : '';
  const тип = классы.filter(function (c) { return c.indexOf('фигура--') === 0 && c !== 'фигура--белая' && c !== 'фигура--чёрная'; })[0];
  return тип ? цвет + ' ' + тип.slice('фигура--'.length) : '';
}

