/** Один элемент: то немногое, что использует игры/шахматы/шахматы-экран.js —
 *  classList/className, атрибуты, appendChild/remove, querySelector (по
 *  потомкам, один класс), closest (по себе и предкам), addEventListener/
 *  click с поддержкой «эмиссии» произвольного target (для делегирования
 *  клика по доске на конкретную клетку). «реестр» — Map id -> элемент
 *  общего document, «всеЭлементы» — плоский список для document.querySelectorAll. */
function создатьЭлемент(тег, реестр, всеЭлементы) {
  const классы = new Set();
  const слушатели = {};
  const атрибуты = {};
  let _id = '';
  const эл = {
    tagName: тег,
    children: [],
    parentElement: null,
    textContent: '',
    disabled: false,
    style: { setProperty: function () {} },
    classList: {
      add: function (c) { классы.add(c); },
      remove: function (c) { классы.delete(c); },
      contains: function (c) { return классы.has(c); },
      toggle: function (c, force) {
        const есть = классы.has(c);
        const нужно = force === undefined ? !есть : Boolean(force);
        if (нужно) классы.add(c); else классы.delete(c);
      }
    },
    setAttribute: function (k, v) { атрибуты[k] = String(v); },
    getAttribute: function (k) { return (k in атрибуты) ? атрибуты[k] : null; },
    removeAttribute: function (k) { delete атрибуты[k]; },
    addEventListener: function (тип, fn) { (слушатели[тип] = слушатели[тип] || []).push(fn); },
    // click() без довода — обычный тап по самому себе; _emit позволяет
    // подсунуть чужой target (делегирование клика доски на клетку).
    click: function () { эл._emit('click', {}); },
    _emit: function (тип, детали) {
      const событие = Object.assign({ target: эл, stopPropagation: function () {}, preventDefault: function () {} }, детали);
      (слушатели[тип] || []).forEach(function (fn) { fn(событие); });
    },
    appendChild: function (реб) {
      if (реб && реб.__fragment) {
        реб.children.slice().forEach(function (внук) { эл.appendChild(внук); });
        реб.children.length = 0;
        return реб;
      }
      эл.children.push(реб);
      реб.parentElement = эл;
      return реб;
    },
    removeChild: function (реб) {
      const индекс = эл.children.indexOf(реб);
      if (индекс !== -1) эл.children.splice(индекс, 1);
      реб.parentElement = null;
      return реб;
    },
    remove: function () { if (эл.parentElement) эл.parentElement.removeChild(эл); },
    querySelector: function (sel) { return найтиПоКлассу(эл, sel.replace(/^\./, '').split(',')[0].trim()); },
    closest: function (sel) {
      const класс = sel.replace(/^\./, '').trim();
      let узел = эл;
      while (узел) {
        if (узел.classList && узел.classList.contains(класс)) return узел;
        узел = узел.parentElement;
      }
      return null;
    },
    focus: function () {}
  };
  /* Как в браузере: запись textContent убирает всех детей — так экран
     перестраивает доску при повороте. */
  let _текст = '';
  delete эл.textContent;
  Object.defineProperty(эл, 'textContent', {
    get: function () { return _текст; },
    set: function (значение) {
      _текст = String(значение);
      эл.children.forEach(function (реб) { реб.parentElement = null; });
      эл.children.length = 0;
    }
  });
  Object.defineProperty(эл, 'id', {
    get: function () { return _id; },
    set: function (значение) { _id = значение; if (реестр) реестр.set(значение, эл); }
  });
  Object.defineProperty(эл, 'className', {
    get: function () { return Array.from(классы).join(' '); },
    set: function (значение) {
      классы.clear();
      String(значение).split(/\s+/).filter(Boolean).forEach(function (c) { классы.add(c); });
    }
  });
  if (всеЭлементы) всеЭлементы.push(эл);
  return эл;
}

function найтиПоКлассу(корень, класс) {
  for (let i = 0; i < корень.children.length; i++) {
    const реб = корень.children[i];
    if (реб.classList.contains(класс)) return реб;
    const вложенный = найтиПоКлассу(реб, класс);
    if (вложенный) return вложенный;
  }
  return null;
}

function создатьФрагмент() {
  return { __fragment: true, children: [], appendChild: function (реб) { this.children.push(реб); return реб; } };
}

/** Поддельный document: getElementById по реестру, querySelectorAll —
 *  упрощённый (одиночный класс или список через запятую; составной
 *  селектор с «>»/пробелом безопасно даёт пустой список — в этом файле
 *  такие селекторы используются только для необязательного слежения
 *  за экранами, см. следитьЗаЭкранамиДляНастроек в шахматы-экран.js). */
function создатьDocument() {
  const реестр = new Map();
  const всеЭлементы = [];
  const слушатели = {};

  function простойПоиск(sel) {
    sel = sel.trim();
    if (/[ >]/.test(sel)) return [];   // комбинаторы — безопасный пустой результат
    if (sel[0] === '#') {
      const эл = реестр.get(sel.slice(1));
      return эл ? [эл] : [];
    }
    const классы = sel.split('.').filter(Boolean);
    if (классы.length === 0) return [];
    return всеЭлементы.filter(function (эл) {
      return классы.every(function (c) { return эл.classList.contains(c); });
    });
  }

  return {
    createElement: function (тег) { return создатьЭлемент(тег, реестр, всеЭлементы); },
    createDocumentFragment: создатьФрагмент,
    getElementById: function (id) { return реестр.get(id) || null; },
    querySelectorAll: function (sel) {
      const результат = [];
      sel.split(',').forEach(function (часть) {
        простойПоиск(часть).forEach(function (эл) { if (результат.indexOf(эл) === -1) результат.push(эл); });
      });
      return результат;
    },
    addEventListener: function (тип, fn) { (слушатели[тип] = слушатели[тип] || []).push(fn); },
    _emit: function (тип) { (слушатели[тип] || []).forEach(function (fn) { fn({}); }); }
  };
}

