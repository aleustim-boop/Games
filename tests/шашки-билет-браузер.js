/* Настоящая подпись initData тем же приёмом, что и в
   tests/профиль-очки-по-играм-сервер.js: HMAC настоящим токеном бота —
   сервер её примет как подлинную (поддельный Telegram сам такую
   подпись не делает, см. tests/поддельный-телеграм.js). */
function подписать(кто) {
  const поля = new URLSearchParams();
  поля.set('user', JSON.stringify(кто));
  поля.set('auth_date', String(Math.floor(Date.now() / 1000)));
  const строки = [];
  for (const пара of поля) строки.push(пара[0] + '=' + пара[1]);
  строки.sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(ТОКЕН).digest();
  поля.set('hash', crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex'));
  return поля.toString();
}

function стукРейтинг(порт, initData, игра) {
  return fetch('http://127.0.0.1:' + порт + '/рейтинг', {
    method: 'POST', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ initData: initData, игра: игра })
  }).then(function (о) { return о.json(); });
}

function закрыть(httpСервер) {
  return new Promise(function (готово) {
    if (!httpСервер) return готово();
    /* Пауза после close() — тот же приём, что в других серверных
       проверках: на Windows node иногда падает с внутренней ошибкой,
       если process.exit() зовут вплотную к колбэку close(). */
    httpСервер.close(function () { setTimeout(готово, 100); });
  });
}

/* ---- Свой маленький статический сервер страниц (playwright не открывает file://). ---- */
const ТИПЫ_ФАЙЛОВ = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.webp': 'image/webp'
};

function поднятьСтатику(корень, порт) {
  const кореньПолный = path.resolve(корень);
  return new Promise(function (готово) {
    const httpСервер = http.createServer(function (запрос, ответ) {
      let адрес;
      try { адрес = decodeURIComponent(запрос.url.split('?')[0]); } catch (ошибка) { адрес = '/некорректно'; }
      if (адрес === '/') адрес = '/index.html';
      const части = адрес.split(/[\\/]/).filter(Boolean);
      const заперто = части.some(function (ч) { return ч.charAt(0) === '.'; }) ||
        (части[0] && части[0].toLowerCase() === 'bot');
      if (заперто) { ответ.writeHead(403); ответ.end('закрыто'); return; }
      const файл = path.join(кореньПолный, части.join(path.sep));
      if (файл !== кореньПолный && !файл.startsWith(кореньПолный + path.sep)) {
        ответ.writeHead(403); ответ.end('закрыто'); return;
      }
      fs.readFile(файл, function (ошибка, данные) {
        if (ошибка) { ответ.writeHead(404); ответ.end('не найдено: ' + адрес); return; }
        ответ.writeHead(200, {
          'Content-Type': ТИПЫ_ФАЙЛОВ[path.extname(файл).toLowerCase()] || 'application/octet-stream',
          'Cache-Control': 'no-store'
        });
        ответ.end(данные);
      });
    });
    httpСервер.listen(порт, '127.0.0.1', function () { готово(httpСервер); });
  });
}

/* ---- Копия проекта для ломающего прогона + порча шашки.html. ---- */
function копияПроекта() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'шашки-билет-копия-'));
  fs.readdirSync(ПРОЕКТ).filter(function (ф) { return /\.html$/.test(ф); }).forEach(function (ф) {
    fs.copyFileSync(path.join(ПРОЕКТ, ф), path.join(папка, ф));
  });
  fs.cpSync(path.join(ПРОЕКТ, 'js'), path.join(папка, 'js'), { recursive: true });
  return папка;
}

function убратьПодключение(файл, скрипт) {
  const текст = fs.readFileSync(файл, 'utf8');
  const экранированный = скрипт.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const образец = new RegExp('<script[^>]*\\ssrc="' + экранированный + '(?:\\?[^"]*)?"[^>]*></script>', 'g');
  const совпадения = текст.match(образец) || [];
  if (совпадения.length !== 1) {
    throw new Error('приём порчи устарел: подключение ' + скрипт + ' в ' + файл + ' встречается ' + совпадения.length + ' раз(а) вместо одного');
  }
  fs.writeFileSync(файл, текст.replace(образец, ''), 'utf8');
}

/* ---- Игровой цикл: тот же приём, что в tests/шашки-партия-пальцем.js. ---- */
async function тапнуть(страница) {
  return страница.evaluate(function () {
    var случайный = function (список) { return список[Math.floor(Math.random() * список.length)]; };
    var куда = document.querySelectorAll('.поле--можно, .поле--можно-бой');
    if (куда.length > 0) { случайный(Array.from(куда)).click(); return 'ход'; }
    var свои = document.querySelectorAll('.фишка--может-ходить');
    if (свои.length > 0) { случайный(Array.from(свои)).parentElement.click(); return 'поднял'; }
    return 'нечего';
  });
}

async function доигратьДоКонца(страница, пределТапов) {
  for (let i = 0; i < пределТапов; i++) {
    const кончено = await страница.evaluate(function () {
      const итог = document.getElementById('экран-итога');
      return Boolean(итог && итог.classList.contains('экран--виден'));
    });
    if (кончено) return i;
    const что = await тапнуть(страница);
    if (что === 'нечего') await страница.waitForTimeout(120);
    else await страница.waitForTimeout(25);
  }
  return -1;
}

async function сыгратьПартиюСБотом(страница, ждатьМсПередТапами) {
  await страница.waitForSelector('#лобби-боты', { state: 'visible', timeout: 15000 });
  await страница.click('#лобби-боты');
  await страница.waitForSelector('#уровень-лёгкий', { state: 'visible', timeout: 10000 });
  await страница.click('#уровень-лёгкий');
  await страница.click('#кнопка-с-ботом');
  await страница.waitForSelector('#экран-шашек.экран--виден', { timeout: 10000 });
  if (ждатьМсПередТапами > 0) {
    console.log('  ждём ' + Math.round(ждатьМсПередТапами / 1000) + ' сек реального времени — иначе билет сочтут «слишком короткой партией»…');
    await страница.waitForTimeout(ждатьМсПередТапами);
  }
  const тапов = await доигратьДоКонца(страница, 1200);
  return тапов;
}

/* ---- Один полный прогон: своя страница, свой игрок, своё ожидание. ---- */
async function одинПрогон(корень, игрок, ждатьМсПередТапами) {
  const итог = { ошибкиКонсоли: [], тапов: -1, ответРейтинга: null, заголовокИтога: '' };

  let httpКомнаты = null;
  let httpСтраницы = null;
  let браузер = null;
  try {
    рейтинг.забытьВсё();
    httpКомнаты = сервер.запустить(ПОРТ_КОМНАТ, 2000);
    httpСтраницы = await поднятьСтатику(корень, ПОРТ_СТРАНИЦ);

    браузер = await chromium.launch();
    const контекст = await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
    const страница = await контекст.newPage();
    /* Настоящий telegram-web-app.js мы САМИ блокируем нарочно (его же
       блокирует подготовитьПодделку/безTelegram) — иначе он затёр бы
       подделку. Отказ его загрузить — не находка про игру, а наша же
       порча, поэтому в список ошибок консоли она не идёт. Всё остальное
       считаем честно. */
    function неНашаБлокировка(текст) { return /telegram-web-app\.js|telegram\.org/.test(текст); }
    /* Игрок в тесте — синтетический номер (981101/981102), которого не
       знает Bot API: server/фото-игроков.js честно ходит в Telegram за
       его фото, ничего не находит, и /фото/<ключ> у него ВСЕГДА 404 —
       это следствие ПОДДЕЛКИ игрока в тесте, а не поломка игры (у живого
       игрока с фото профиля тот же путь отдал бы настоящую картинку).
       Фильтр нарочно узкий: только адрес, начинающийся с «/фото/», и
       именно ответ 404 — 404 на любом другом адресе, как и любая другая
       сетевая беда, по-прежнему считается и красит проверку. */
    function этоФото404(url, статус) {
      if (статус !== 404) return false;
      try { return decodeURIComponent(new URL(url).pathname).indexOf('/фото/') === 0; }
      catch (е) { return false; }
    }
    const сыраяКонсоль = [];            // {текст, url} — решаем судьбу после того, как узнаем про /фото/ из ответов
    const известныеФото404 = new Set(); // decoded-путь ресурсов «/фото/…», на которые сервер САМ ответил 404
    страница.on('pageerror', function (о) { итог.ошибкиКонсоли.push('исключение: ' + о.message); });
    страница.on('console', function (с) {
      if (с.type() !== 'error') return;
      /* «Failed to load resource: net::ERR_FAILED» — общий текст без адреса
         (текст telegram-web-app.js в него не попадает никогда, только в
         location() сообщения), поэтому саму блокировку тоже проверяем по
         адресу источника, а не по тексту — иначе она осталась бы красной. */
      const место = с.location();
      const адресИсточника = место && место.url;
      if (адресИсточника && неНашаБлокировка(адресИсточника)) return;
      if (!адресИсточника && неНашаБлокировка(с.text())) return;
      сыраяКонсоль.push({ текст: 'консоль: ' + с.text(), url: адресИсточника });
    });
    /* Само сообщение консоли про «Failed to load resource» не содержит
       адрес — добавляем его отдельно по сетевым событиям, чтобы отчёт
       называл КОНКРЕТНЫЙ файл, а не просто «что-то не загрузилось». */
    страница.on('requestfailed', function (з) {
      if (неНашаБлокировка(з.url())) return;
      итог.ошибкиКонсоли.push('сеть: не загрузилось ' + з.url() + ' (' + (з.failure() && з.failure().errorText) + ')');
    });
    страница.on('response', function (о) {
      if (неНашаБлокировка(о.url()) || о.status() < 400) return;
      if (этоФото404(о.url(), о.status())) {
        try { известныеФото404.add(decodeURIComponent(new URL(о.url()).pathname)); } catch (е) { /* нарочно молчим */ }
        return;
      }
      итог.ошибкиКонсоли.push('сеть: ' + о.status() + ' на ' + о.url());
    });

    const initData = подписать({ id: игрок, first_name: 'Тестошашист' });
    await подготовитьПодделку(страница, { подпись: initData, версия: '7.10' });

    await страница.goto('http://127.0.0.1:' + ПОРТ_СТРАНИЦ + '/шашки.html?сервер=' +
      encodeURIComponent('http://127.0.0.1:' + ПОРТ_КОМНАТ));

    итог.тапов = await сыгратьПартиюСБотом(страница, ждатьМсПередТапами);
    итог.заголовокИтога = await страница.evaluate(function () {
      const узел = document.getElementById('заголовок-итога');
      return узел ? узел.textContent : '';
    });

    await страница.waitForTimeout(800);   // дать время на сам fetch «/итог-с-ботом»

    /* Разбор отложенных консольных сообщений: то же самое событие
       «Failed to load resource», для которого мы уже видели настоящий
       ответ 404 на «/фото/…», в подсчёт не идёт — остальное честно
       добавляем, даже если текст похож («Failed to load resource»
       бывает и для других адресов). */
    сыраяКонсоль.forEach(function (запись) {
      let этоТотЖеФото404 = false;
      if (запись.url) {
        try { этоТотЖеФото404 = известныеФото404.has(decodeURIComponent(new URL(запись.url).pathname)); }
        catch (е) { /* нарочно молчим */ }
      }
      if (!этоТотЖеФото404) итог.ошибкиКонсоли.push(запись.текст);
    });

    await браузер.close();
    браузер = null;

    итог.ответРейтинга = await стукРейтинг(ПОРТ_КОМНАТ, initData, 'шашки');
  } finally {
    if (браузер) await браузер.close();
    await закрыть(httpКомнаты);
    await закрыть(httpСтраницы);
  }
  return итог;
}

/* =====================================================================
   Обычный прогон — настоящая страница, партия честно длится > 60 сек
   ===================================================================== */

async function прогнатьОбычный() {
  console.log('=== Шашки: билет и рейтинг после партии с лёгким ботом (обычный прогон) ===');
  console.log('Порт комнат: ' + ПОРТ_КОМНАТ + ', порт страниц: ' + ПОРТ_СТРАНИЦ + ' (боевой 8790 не трогаем)\n');

  const итог = await одинПрогон(ПРОЕКТ, ИГРОК_ОБЫЧНЫЙ, 62000);

  проверить(итог.тапов >= 0, 'партия с ботом доиграна до итога, тапов: ' + итог.тапов);
  console.log('  итог партии на экране: «' + итог.заголовокИтога + '»');

  const ответ = итог.ответРейтинга;
  проверить(!!ответ && ответ.ок === true, 'POST /рейтинг ответил ок:true, получили: ' + JSON.stringify(ответ && { ок: ответ.ок, причина: ответ.причина }));
  проверить(!!ответ && ответ.узналиВас === true, 'сервер узнал игрока по подписи (узналиВас:true)');
  проверить(!!ответ && ответ.я && ответ.я.партий === 1,
    'в таблице рейтинга у игрока ровно 1 партия шашек, получили «я»: ' + JSON.stringify(ответ && ответ.я));
  проверить(итог.ошибкиКонсоли.length === 0,
    'красных ошибок в консоли нет' + (итог.ошибкиКонсоли.length ? ': ' + итог.ошибкиКонсоли.join(' | ') : ''));
}

/* =====================================================================
   Ломающий прогон — копия страницы шашек БЕЗ js/очки-рейтинга.js:
   билета не будет никакого, ждать 60 секунд незачем.
   ===================================================================== */

async function прогнатьЛомающий() {
  console.log('=== Ломающий прогон --сломать: копия шашки.html без js/очки-рейтинга.js ===\n');
  console.log('Как читать итог: ниже НЕ «партия сломалась», а «проверка обязана покраснеть» —');
  console.log('по правилу проекта ломающий запуск считается удачным, только если итог красный.\n');

  const папка = копияПроекта();
  try {
    убратьПодключение(path.join(папка, 'шашки.html'), 'js/очки-рейтинга.js');

    const итог = await одинПрогон(папка, ИГРОК_ЛОМАЮЩИЙ, 0);

    /* Предпосылки — сама инфраструктура порчи должна отработать, иначе
       непонятно, порча ли не сработала или сломался сам стенд. Это НЕ
       та порча, которую мы ждём, — обычные «ок»/«плохо». */
    проверить(итог.тапов >= 0, 'партия на испорченной копии всё равно доиграна до итога, тапов: ' + итог.тапов);
    console.log('  итог партии на экране: «' + итог.заголовокИтога + '»');
    const ответ = итог.ответРейтинга;
    проверить(!!ответ && ответ.ок === true, 'POST /рейтинг всё равно отвечает ок:true (игрока сервер знает)');
    console.log('  ответ /рейтинг: я=' + JSON.stringify(ответ && ответ.я) + ', яВТаблице=' + (ответ && ответ.яВТаблице));

    /* ГЛАВНАЯ строка ломающего прогона: без js/очки-рейтинга.js билет
       взять некому, партия в таблицу рейтинга не попадает — сервер
       честно отвечает я:null, яВТаблице:false (не объект с нулями,
       см. server/рейтинг.js). Это и есть «строки в рейтинге нет»
       из задания. Проверка ОБЯЗАНА покраснеть именно тут: если она
       увидела ровно это отсутствие строки — порча удалась, засчитываем
       её как ожидаемый провал. Если строка вдруг ЕСТЬ — стенд «слеп»
       и не годится ловить эту поломку, это тоже провал, но по другой,
       куда более тревожной причине. */
    проверок++;
    const строкиВРейтингеНет = !!ответ && ответ.яВТаблице === false && ответ.я === null;
    if (строкиВРейтингеНет) {
      провалов++;
      console.log('  ПРОВАЛ (ожидаемый) — без js/очки-рейтинга.js партия в рейтинг не попала: строки игрока в таблице нет.');
    } else {
      провалов++;
      console.log('  СЛЕПА — порча не дала ожидаемого эффекта: партия ВСЁ РАВНО попала в рейтинг (я: ' +
        JSON.stringify(ответ && ответ.я) + '). Проверка не ловит эту поломку — почините стенд.');
    }
  } finally {
    fs.rmSync(папка, { recursive: true, force: true });
  }
}

/* ---------------- Запуск ---------------- */

(async function () {
  try {
    if (ЛОМАТЬ) await прогнатьЛомающий();
    else await прогнатьОбычный();
  } catch (беда) {
    провалов++;
    проверок++;
    console.log('ПРОВЕРКА ОБОРВАЛАСЬ: ' + беда.message);
    console.log(беда.stack);
  } finally {
    try { fs.rmSync(СВОЯ_ПАПКА, { recursive: true, force: true }); } catch (е) { /* нарочно молчим */ }
  }
  console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
})();
