/* =====================================================================
   ШАШКИ: БИЛЕТ И РЕЙТИНГ ПОСЛЕ ПАРТИИ С БОТОМ — ЖИВОЙ БРАУЗЕРНЫЙ ПРОГОН.

   Node-скрипт tests/билет-в-каждой-игре-с-ботом.js читает ТЕКСТ файлов
   и не может проверить главное: что билет и правда доезжает до сервера
   и партия правда появляется в таблице рейтинга. Этот файл — один
   настоящий прогон: открываем шашки.html настоящим браузером, поддельный
   Telegram даёт подпись игрока, играем партию с лёгким ботом ПАЛЬЦЕМ
   до конца, ждём отправки билета — и спрашиваем у сервера комнат
   POST /рейтинг?игра=шашки: игрок должен появиться там с 1 партией.

   ПРО ШЕСТЬДЕСЯТ СЕКУНД. server/билеты.js отказывает в очках партии
   короче правдоподобной (js/игры-реестр.js: у шашек партияНеКорочеСекунд
   = 60) — сравнивает РЕАЛЬНОЕ время между взятием билета (старт партии)
   и его сдачей (показ итога). Тапы playwright делает за миллисекунды,
   поэтому между стартом и первым тапом стенд просто ждёт часами
   компьютера чуть больше 60 секунд, а уже потом дотапывает партию до
   конца — это не имитация игры, а самый дешёвый способ сделать разницу
   времени честной. Ломающий прогон это ожидание пропускает: там билета
   всё равно не будет никакого, ждать нечего.

   Сервер комнат — тот же приём, что у tests/профиль-очки-по-играм-сервер.js:
   require('../server/сервер.js') и вызов .запустить(порт) В ЭТОМ ЖЕ
   процессе, на порту, который не 8790 (боевой сервер комнат не трогаем).
   «--без-памяти» получаем тем же способом, каким его получают все
   серверные проверки этого стиля: НЕ зовём рейтинг.включитьЗапись() —
   партии считаются только в памяти процесса и на диск не попадают,
   плюс GAMES_DATA уведена в свою временную папку до require. Гасим
   сервер закрытием HTTP-сокета (httpСервер.close()) — сервер живёт
   в ЭТОМ процессе теста, значит его PID — это PID самого теста:
   отдельного child_process с сервером комнат этот стенд не заводит
   (ровно так это устроено во всех существующих браузерных+серверных
   проверках проекта — отдельный процесс под node тут не принят).

   Страницы игры отдаёт свой маленький статический сервер (playwright
   не умеет file://) — либо настоящий проект, либо, в ломающем прогоне,
   ЕГО КОПИЯ во временной папке с испорченной шашки.html; исходники
   проекта porчей не касаются.

   Запуск:
       node tests/шашки-билет-браузер.js            — обычный прогон (~80–90 сек)
       node tests/шашки-билет-браузер.js --сломать   — ломающий прогон (копия
         страницы шашек без <script src="js/очки-рейтинга.js">, партия играется
         сразу, без часового ожидания — билета там всё равно не будет)

   Перед стартом обязательно проверяет штаб/браузер-занят.js --ждать —
   безголовых браузеров проверок разом не больше трёх.
   ===================================================================== */

