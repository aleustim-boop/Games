/* =====================================================================
   ЧУЖОЙ БОЙ ДОЛЖНО БЫТЬ ВИДНО ПО ШАГАМ.

   Владелец жаловался лично: «когда играю в шашки, не понятно, как бьёт
   противник, нужно замедлить и показать его шаги». Показ сделали — и он
   ТРИ НЕДЕЛИ молча не работал: экран ждал цвет ходившего, сервер слал
   «мой ход или не мой», условие не сходилось. Ни ошибки, ни следа
   в консоли — поломка, которую видно только глазами.

   Поэтому здесь проверяется не «поле приехало», а «шаги видно»:

     1. чужая шашка идёт ПО КЛЕТКАМ пути, а не оказывается на конце разом;
     2. побитые шашки исчезают В КОНЦЕ цепочки, а не сразу все.

   Как устроено, чтобы не кликать десятки раз руками. За доской двое:
     • НАШ СОПЕРНИК — этот скрипт, ходит по сети обычными запросами
       и умеет выбрать именно цепочку боя из двух и более взятий;
     • ИГРОК — настоящая страница в браузере, свои ходы делает тапами
       по подсвеченным клеткам (как человек).
   Когда у соперника появляется цепочка, стенд включает наблюдателя за
   доской в браузере (снимок каждые 40 мс) и смотрит, что увидел глаз.

   Запуск (страничный сервер и сервер комнат уже подняты):
       node tests/чужой-бой-по-шагам.js 8080 8794
   ===================================================================== */

const http = require('http');
const path = require('path');
const Правила = require(path.join(__dirname, '..', 'js', 'шашки-правила.js'));
const { chromium, подготовитьПодделку } = require('./браузер-робот.js');

const ПОРТ_СТРАНИЦ = Number(process.argv[2]) || 8080;
const ПОРТ_КОМНАТ = Number(process.argv[3]) || 8794;
const ХОСТ = '127.0.0.1';
const ПОТОЛОК_ХОДОВ = 600;

let провалов = 0;
function проверить(условие, слова) {
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}

function запрос(путь, тело) {
  return new Promise(function (готово, беда) {
    const текст = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const о = http.request({
      host: ХОСТ, port: ПОРТ_КОМНАТ, method: 'POST', path: encodeURI(путь),
      headers: { 'Content-Type': 'application/json', 'Content-Length': текст.length }
    }, function (ответ) {
      let к = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (ч) { к += ч; });
      ответ.on('end', function () { try { готово(JSON.parse(к)); } catch (сбой) { готово({}); } });
    });
    о.on('error', беда);
    о.end(текст);
  });
}

const спать = (мс) => new Promise((ф) => setTimeout(ф, мс));

/** Ходы из присланной картинки — теми же правилами, что и у страницы. */
function ходыИз(вид) {
  return Правила.возможныеХоды(Правила.партияИзКартинки(вид.доска, вид.чейХод));
}

