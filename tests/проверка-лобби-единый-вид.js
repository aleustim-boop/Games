// Проверка: правки в лобби-экранах не сломали HTML и CSS
// Проверяет, что классы применены правильно и селекторы JS не повреждены

const fs = require('fs');
const path = require('path');

let ошибки = [];
let предупреждения = [];

// 1. Проверка index.html (дурак)
const index = fs.readFileSync('index.html', 'utf-8');

if (!index.includes('h1 class="лобби__заголовок">Дурак</h1>')) {
  ошибки.push('index.html: заголовок лобби дурака повреждён');
}

if (!index.includes('<p class="подпись">Народная игра для компании</p>')) {
  ошибки.push('index.html: новая подпись под заголовком не найдена');
}

if (!index.includes('id="лобби-друзья"')) {
  ошибки.push('index.html: карточка "Пригласить друзей" не найдена (id не совпадает)');
}

if (index.includes('id="лобби-друзья"')) {
  const картаПригласить = index.match(/id="лобби-друзья"[\s\S]*?<\/button>/);
  if (картаПригласить && !картаПригласить[0].includes('Позовите компанию')) {
    ошибки.push('index.html: подпись "Позовите компанию" не найдена в карточке "Пригласить друзей"');
  }
}

// Проверка класса для "Найти игру" в дураке
if (!index.includes('id="лобби-онлайн"')) {
  ошибки.push('index.html: карточка "Найти игру" не найдена (id="лобби-онлайн")');
} else {
  const картаНайти = index.match(/id="лобби-онлайн"[\s\S]*?class="([^"]*)"[\s\S]*?<\/button>/);
  if (картаНайти) {
    const классы = картаНайти[1];
    if (!классы.includes('карточка-входа--онлайн')) {
      ошибки.push('index.html: карточка "Найти игру" не имеет класса карточка-входа--онлайн');
    }
  }
}

// 2. Проверка шашки.html
const шашки = fs.readFileSync('шашки.html', 'utf-8');

if (!шашки.includes('h1 class="лобби__заголовок">Шашки</h1>')) {
  ошибки.push('шашки.html: заголовок лобби шашек повреждён');
}

if (!шашки.includes('<p class="подпись">Классическая игра для двоих</p>')) {
  ошибки.push('шашки.html: новая подпись под заголовком не найдена');
}

// Проверка карточки "Найти игру" в шашках
if (!шашки.includes('id="лобби-найти-игру"')) {
  ошибки.push('шашки.html: карточка "Найти игру" не найдена (id="лобби-найти-игру")');
} else {
  const картаНайти = шашки.match(/id="лобби-найти-игру"[\s\S]*?class="([^"]*)"[\s\S]*?>/);
  if (картаНайти) {
    const классы = картаНайти[1];
    if (!классы.includes('карточка-входа--онлайн')) {
      ошибки.push('шашки.html: карточка "Найти игру" не имеет класса карточка-входа--онлайн');
    }
    if (классы.includes('карточка-входа--вдвоём')) {
      ошибки.push('шашки.html: карточка "Найти игру" всё ещё имеет класс карточка-входа--вдвоём');
    }
  }
}

// Проверка карточки "Вдвоём на этом устройстве" в шашках
if (!шашки.includes('id="лобби-вдвоём"')) {
  ошибки.push('шашки.html: карточка "Вдвоём" не найдена (id="лобби-вдвоём")');
} else {
  const картаВдвоём = шашки.match(/id="лобби-вдвоём"[\s\S]*?class="([^"]*)"[\s\S]*?>/);
  if (картаВдвоём) {
    const классы = картаВдвоём[1];
    if (!классы.includes('карточка-входа--вдвоём')) {
      ошибки.push('шашки.html: карточка "Вдвоём" не имеет класса карточка-входа--вдвоём');
    }
  }
}

// 3. Проверка CSS классов в style.css
const css = fs.readFileSync('style.css', 'utf-8');

if (!css.includes('.подпись')) {
  ошибки.push('style.css: класс .подпись не найден');
}

if (!css.includes('.карточка-входа__подпись')) {
  ошибки.push('style.css: класс .карточка-входа__подпись не найден');
}

if (!css.includes('.карточка-входа--онлайн')) {
  ошибки.push('style.css: класс .карточка-входа--онлайн не найден');
}

if (!css.includes('.карточка-входа--вдвоём')) {
  ошибки.push('style.css: класс .карточка-входа--вдвоём не найден');
}

// 4. Проверка JS: классы не должны быть селекторами
const jsФайлы = ['js/открытые-столы.js', 'js/шашки-экран.js', 'js/сеть.js'];

for (const файл of jsФайлы) {
  if (fs.existsSync(файл)) {
    const код = fs.readFileSync(файл, 'utf-8');

    // Ищем использование классов как селекторов (опасно)
    // querySelector('.карточка-входа--вдвоём') или класс '.карточка-входа--онлайн'
    if (код.includes('.карточка-входа--вдвоём') || код.includes('.карточка-входа--онлайн')) {
      // Проверяем, что это не просто комментарий
      const строки = код.split('\n');
      for (let i = 0; i < строки.length; i++) {
        if (строки[i].includes('.карточка-входа--вдвоём') || строки[i].includes('.карточка-входа--онлайн')) {
          if (!строки[i].trim().startsWith('//')) {
            предупреждения.push(`${файл}:${i+1}: возможное использование класса как селектора`);
          }
        }
      }
    }
  }
}

// Результаты
console.log('\n=== Проверка лобби-экранов (единый вид) ===\n');

if (ошибки.length === 0 && предупреждения.length === 0) {
  console.log('✓ ВСЁ В ПОРЯДКЕ');
  console.log('  - index.html: новая подпись и структура верны');
  console.log('  - шашки.html: новая подпись, класс--онлайн на месте, класс--вдвоём не мешает');
  console.log('  - style.css: все классы определены');
  console.log('  - JS: селекторы по id, не по классам');
  process.exit(0);
}

if (ошибки.length > 0) {
  console.log('✗ ОШИБКИ:');
  for (const ошибка of ошибки) {
    console.log('  ' + ошибка);
  }
}

if (предупреждения.length > 0) {
  console.log('\n⚠ ПРЕДУПРЕЖДЕНИЯ:');
  for (const предупр of предупреждения) {
    console.log('  ' + предупр);
  }
}

process.exit(ошибки.length > 0 ? 1 : 0);
