// Проверка: правки в лобби-экранах не сломали HTML и CSS
// Проверяет, что классы применены правильно и селекторы JS не повреждены

const fs = require('fs');
const path = require('path');
const os = require('os');
const { spawnSync } = require('child_process');

// Ломающий запуск (--сломать): проверка обязана уметь краснеть. Берём
// index.html и портим его КОПИЮ во временной папке (сам файл игры не
// трогаем), затем натравливаем на копию обычный прогон этого же файла
// и требуем, чтобы он провалился. Не провалился — проверка слепая.
if (process.argv.includes('--сломать')) {
  запуститьЛомающийПрогон();
  return;
}

function запуститьЛомающийПрогон() {
  const кореньПроекта = path.join(__dirname, '..');
  const индексОригинал = fs.readFileSync(path.join(кореньПроекта, 'index.html'), 'utf-8');
  const шашкиОригинал = fs.readFileSync(path.join(кореньПроекта, 'шашки.html'), 'utf-8');

  // Поле «файл» говорит, какую страницу портит сценарий — 'index.html'
  // (дурак) или 'шашки.html'. По умолчанию — index.html.
  const сценарии = [
    {
      имя: 'на главном экране лобби снова четыре входа (вернулась карточка «лобби-онлайн»)',
      файл: 'index.html',
      испортить(html) {
        return html.replace(
          '<div class="лобби__входы">',
          '<div class="лобби__входы">\n      <button id="лобби-онлайн" type="button" class="карточка-входа карточка-входа--онлайн">Найти игру</button>'
        );
      }
    },
    {
      имя: 'входы на главном экране лобби переставлены местами (друзья раньше онлайна)',
      файл: 'index.html',
      испортить(html) {
        return html
          .replace('id="лобби-играть-онлайн"', 'id="лобби-временная-метка"')
          .replace('id="лобби-друзья"', 'id="лобби-играть-онлайн"')
          .replace('id="лобби-временная-метка"', 'id="лобби-друзья"');
      }
    },
    {
      имя: 'в лобби шашек у карточки «Найти игру» пропал класс карточка-входа--играть-онлайн',
      файл: 'шашки.html',
      испортить(html) {
        return html.replace(
          'id="лобби-найти-игру" type="button" class="карточка-входа карточка-входа--играть-онлайн"',
          'id="лобби-найти-игру" type="button" class="карточка-входа"'
        );
      }
    },
    {
      имя: 'в лобби шашек карточки «боты» и «вдвоём» переставлены местами',
      файл: 'шашки.html',
      испортить(html) {
        return html
          .replace('id="лобби-боты"', 'id="лобби-временная-метка"')
          .replace('id="лобби-вдвоём"', 'id="лобби-боты"')
          .replace('id="лобби-временная-метка"', 'id="лобби-вдвоём"');
      }
    }
  ];

  console.log('\n=== Ломающий запуск: проверка обязана краснеть ===\n');

  let провалов = 0;

  for (const сценарий of сценарии) {
    const портимШашки = сценарий.файл === 'шашки.html';
    const исходныйHtml = портимШашки ? шашкиОригинал : индексОригинал;
    const испорченныйHtml = сценарий.испортить(исходныйHtml);
    if (испорченныйHtml === исходныйHtml) {
      console.log('✗ сценарий "' + сценарий.имя + '" не изменил ' + сценарий.файл + ' — испортитель сломан, чинить его');
      провалов++;
      continue;
    }

    const временнаяПапка = fs.mkdtempSync(path.join(os.tmpdir(), 'проверка-лобби-'));
    try {
      fs.writeFileSync(path.join(временнаяПапка, 'index.html'), портимШашки ? индексОригинал : испорченныйHtml, 'utf-8');
      fs.writeFileSync(path.join(временнаяПапка, 'шашки.html'), портимШашки ? испорченныйHtml : шашкиОригинал, 'utf-8');
      fs.copyFileSync(path.join(кореньПроекта, 'style.css'), path.join(временнаяПапка, 'style.css'));

      // Прогоняем этот же файл проверки (без --сломать) над испорченной
      // копией: рабочая папка — временная, поэтому относительные пути
      // ('index.html', 'шашки.html', 'style.css') внутри проверки прочитают
      // именно испорченные файлы, а не настоящие файлы игры.
      const результат = spawnSync(process.execPath, [__filename], { cwd: временнаяПапка, encoding: 'utf-8' });

      if (результат.status === 0) {
        console.log('✗ ПРОВЕРКА СЛЕПАЯ: сценарий "' + сценарий.имя + '" обязан был провалить проверку, а она прошла зелёной');
        провалов++;
      } else {
        console.log('✓ проверка покраснела на сценарии: ' + сценарий.имя);
      }
    } finally {
      fs.rmSync(временнаяПапка, { recursive: true, force: true });
    }
  }

  console.log(`\nИтого сценариев: ${сценарии.length}, провалов: ${провалов}`);
  process.exit(провалов > 0 ? 1 : 0);
}

let ошибки = [];
let предупреждения = [];

// 1. Проверка index.html (дурак)
const index = fs.readFileSync('index.html', 'utf-8');

if (!index.includes('h1 class="лобби__заголовок">Дурак</h1>')) {
  ошибки.push('index.html: заголовок лобби дурака повреждён');
}

if (!index.includes('<p class="подпись">Народная игра для компании</p>')) {
  ошибки.push('index.html: новая подпись под заголовком не найдена');
}

if (!index.includes('id="лобби-друзья"')) {
  ошибки.push('index.html: карточка "Пригласить друзей" не найдена (id не совпадает)');
}

if (index.includes('id="лобби-друзья"')) {
  const картаПригласить = index.match(/id="лобби-друзья"[\s\S]*?<\/button>/);
  if (картаПригласить && !картаПригласить[0].includes('Позовите друзей в приложение')) {
    ошибки.push('index.html: подпись "Позовите друзей в приложение" не найдена в карточке "Пригласить друзей"');
  }
}

// Главный экран лобби дурака — ровно три входа, в порядке владельца:
// «Играть онлайн», «Играть с ботами», «Пригласить друзей». Старые узлы
// «лобби-онлайн» («Найти игру») и «лобби-код» («Есть код? Войти») уехали
// внутрь будущего экрана «Играть онлайн» — на главном их быть не должно.
const ожидаемыйПорядокВходов = ['лобби-играть-онлайн', 'лобби-боты', 'лобби-друзья'];

if (index.includes('id="лобби-онлайн"')) {
  ошибки.push('index.html: узел "лобби-онлайн" ("Найти игру") должен был уйти с главного экрана лобби');
}

if (index.includes('id="лобби-код"')) {
  ошибки.push('index.html: узел "лобби-код" ("Есть код? Войти") должен был уйти с главного экрана лобби');
}

// Блок входов лежит между картинкой лобби и нижними вкладками —
// вырезаем его, чтобы посчитать порядок кнопок именно внутри лобби,
// а не по всему файлу (в других экранах могут быть свои узлы).
const началоВходов = index.indexOf('class="лобби__входы"');
const конецВходов = index.indexOf('нижние-вкладки', началоВходов);
if (началоВходов === -1 || конецВходов === -1) {
  ошибки.push('index.html: блок "лобби__входы" на главном экране лобби не найден');
} else {
  const блокВходов = index.slice(началоВходов, конецВходов);
  const найденныйПорядок = [...блокВходов.matchAll(/id="(лобби-[а-яё-]+)"/g)].map(м => м[1]);

  if (найденныйПорядок.length !== ожидаемыйПорядокВходов.length ||
      найденныйПорядок.some((id, i) => id !== ожидаемыйПорядокВходов[i])) {
    ошибки.push('index.html: на главном экране лобби должны быть ровно три входа в порядке ' +
      ожидаемыйПорядокВходов.join(', ') + ' — найдено: ' + найденныйПорядок.join(', ') + '');
  }

  for (const id of ожидаемыйПорядокВходов) {
    if (!блокВходов.includes('id="' + id + '"')) {
      ошибки.push('index.html: карточка входа "' + id + '" не найдена в блоке "лобби__входы"');
    }
  }
}

// 2. Проверка шашки.html
const шашки = fs.readFileSync('шашки.html', 'utf-8');

if (!шашки.includes('h1 class="лобби__заголовок">Шашки</h1>')) {
  ошибки.push('шашки.html: заголовок лобби шашек повреждён');
}

if (!шашки.includes('<p class="подпись">Классическая игра для двоих</p>')) {
  ошибки.push('шашки.html: новая подпись под заголовком не найдена');
}

// Проверка карточки "Найти игру" в шашках. Класс называется
// «карточка-входа--играть-онлайн» — ТАК ЖЕ, как у дурака, нард и шахмат
// (index.html, нарды.html, шахматы.html): у шашек нет своего id
// «лобби-играть-онлайн» (его жёстко ищет js/открытые-столы.js под именем
// «лобби-найти-игру»), но КЛАСС карточки — общий с эталоном дурака.
if (!шашки.includes('id="лобби-найти-игру"')) {
  ошибки.push('шашки.html: карточка "Найти игру" не найдена (id="лобби-найти-игру")');
} else {
  const картаНайти = шашки.match(/id="лобби-найти-игру"[\s\S]*?class="([^"]*)"[\s\S]*?>/);
  if (картаНайти) {
    const классы = картаНайти[1];
    if (!классы.includes('карточка-входа--играть-онлайн')) {
      ошибки.push('шашки.html: карточка "Найти игру" не имеет класса карточка-входа--играть-онлайн');
    }
    if (классы.includes('карточка-входа--вдвоём')) {
      ошибки.push('шашки.html: карточка "Найти игру" всё ещё имеет класс карточка-входа--вдвоём');
    }
  }
}

// Проверка карточки "Вдвоём на этом устройстве" в шашках
if (!шашки.includes('id="лобби-вдвоём"')) {
  ошибки.push('шашки.html: карточка "Вдвоём" не найдена (id="лобби-вдвоём")');
} else {
  const картаВдвоём = шашки.match(/id="лобби-вдвоём"[\s\S]*?class="([^"]*)"[\s\S]*?>/);
  if (картаВдвоём) {
    const классы = картаВдвоём[1];
    if (!классы.includes('карточка-входа--вдвоём')) {
      ошибки.push('шашки.html: карточка "Вдвоём" не имеет класса карточка-входа--вдвоём');
    }
  }
}

// Главный экран лобби шашек — РОВНО ЧЕТЫРЕ карточки-входа, в порядке
// владельца (правка 24.09): «Играть онлайн», «Играть с ботом», «Вдвоём
// на этом устройстве» (теперь тоже полноценная карточка, не мелкая
// кнопка), «Пригласить друзей». Ищем именно кнопки с классом
// «карточка-входа» — «лобби-код» («Есть код? Войти») в том же блоке
// тоже начинается с «лобби-», но это текстовая ссылка, не карточка,
// и её в счёт не берём.
const ожидаемыйПорядокВходовШашек = ['лобби-найти-игру', 'лобби-боты', 'лобби-вдвоём', 'лобби-друзья'];

const началоВходовШашек = шашки.indexOf('class="лобби__входы"');
const конецВходовШашек = шашки.indexOf('нижние-вкладки', началоВходовШашек);
if (началоВходовШашек === -1 || конецВходовШашек === -1) {
  ошибки.push('шашки.html: блок "лобби__входы" на главном экране лобби не найден');
} else {
  const блокВходовШашек = шашки.slice(началоВходовШашек, конецВходовШашек);
  const найденныйПорядокШашек = [...блокВходовШашек.matchAll(/<button id="(лобби-[а-яёА-ЯЁ-]+)"[^>]*class="карточка-входа/g)]
    .map((м) => м[1]);

  if (найденныйПорядокШашек.length !== ожидаемыйПорядокВходовШашек.length ||
      найденныйПорядокШашек.some((id, i) => id !== ожидаемыйПорядокВходовШашек[i])) {
    ошибки.push('шашки.html: на главном экране лобби должны быть ровно четыре карточки-входа в порядке ' +
      ожидаемыйПорядокВходовШашек.join(', ') + ' — найдено: ' + (найденныйПорядокШашек.join(', ') || '(ничего)'));
  }
}

// 3. Проверка CSS классов в style.css
const css = fs.readFileSync('style.css', 'utf-8');

if (!css.includes('.подпись')) {
  ошибки.push('style.css: класс .подпись не найден');
}

if (!css.includes('.карточка-входа__подпись')) {
  ошибки.push('style.css: класс .карточка-входа__подпись не найден');
}

if (!css.includes('.карточка-входа--играть-онлайн')) {
  ошибки.push('style.css: класс .карточка-входа--играть-онлайн не найден');
}

if (!css.includes('.карточка-входа--вдвоём')) {
  ошибки.push('style.css: класс .карточка-входа--вдвоём не найден');
}

// 4. Проверка JS: классы не должны быть селекторами
const jsФайлы = ['js/открытые-столы.js', 'js/шашки-экран.js', 'js/сеть.js'];

for (const файл of jsФайлы) {
  if (fs.existsSync(файл)) {
    const код = fs.readFileSync(файл, 'utf-8');

    // Ищем использование классов как селекторов (опасно)
    // querySelector('.карточка-входа--вдвоём') или класс '.карточка-входа--играть-онлайн'
    if (код.includes('.карточка-входа--вдвоём') || код.includes('.карточка-входа--играть-онлайн')) {
      // Проверяем, что это не просто комментарий
      const строки = код.split('\n');
      for (let i = 0; i < строки.length; i++) {
        if (строки[i].includes('.карточка-входа--вдвоём') || строки[i].includes('.карточка-входа--играть-онлайн')) {
          if (!строки[i].trim().startsWith('//')) {
            предупреждения.push(`${файл}:${i+1}: возможное использование класса как селектора`);
          }
        }
      }
    }
  }
}

// Результаты
console.log('\n=== Проверка лобби-экранов (единый вид) ===\n');

if (ошибки.length === 0 && предупреждения.length === 0) {
  console.log('✓ ВСЁ В ПОРЯДКЕ');
  console.log('  - index.html: новая подпись и структура верны');
  console.log('  - шашки.html: новая подпись, класс --играть-онлайн на месте, четыре карточки-входа по порядку');
  console.log('  - style.css: все классы определены');
  console.log('  - JS: селекторы по id, не по классам');
  process.exit(0);
}

if (ошибки.length > 0) {
  console.log('✗ ОШИБКИ:');
  for (const ошибка of ошибки) {
    console.log('  ' + ошибка);
  }
}

if (предупреждения.length > 0) {
  console.log('\n⚠ ПРЕДУПРЕЖДЕНИЯ:');
  for (const предупр of предупреждения) {
    console.log('  ' + предупр);
  }
}

process.exit(ошибки.length > 0 ? 1 : 0);
