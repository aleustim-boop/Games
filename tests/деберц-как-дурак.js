проверить(/исход === 'победа' && можноХвастаться\(\)/.test(итог), '«Похвастаться» — только после победы (с ботом и по сети)');
проверить(/<p id="итог-рейтинга"[^>]*скрыт/.test(html), 'строка «итог-рейтинга» на месте и спрятана');
проверить(/ОчкиРейтинга\.словаИтога\(/.test(экран), 'строка рейтинга пишется через ОчкиРейтинга.словаИтога');
