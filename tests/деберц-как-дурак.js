проверить(/лист-ещё__подпись">Рекорды</.test(лист), 'строка называется «Рекорды»');
проверить(!/Мои результаты/.test(лист), '«Мои результаты» в листе нет');

// 6. Подключения на странице.
console.log('\n6. Подключения');
проверить(/<script src="js\/очки-рейтинга\.js/.test(html), 'js/очки-рейтинга.js подключён');
const илиПохвастаться = html.indexOf('<script src="js/похвастаться.js'), илиСеть = html.indexOf('<script src="js/сеть.js');
