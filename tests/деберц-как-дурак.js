console.log('\n1. Карточка профиля');
const профиль = кусок(html, '<button id="лобби-профиль"', '</button>');
проверить(профиль.length > 0, 'карточка «лобби-профиль» найдена');
проверить(/id="лобби-аватар"/.test(профиль), 'аватар «лобби-аватар»');
проверить(/id="лобби-рейтинг"[^>]*карточка-профиля__рейтинг--нет/.test(профиль), 'строка «лобби-рейтинг» с классом --нет (пока места нет)');
проверить(/id="лобби-место"/.test(профиль), 'в карточке есть узел «лобби-место»');
проверить(!/лобби-серия/.test(html) && !/лобби-серия/.test(экран), 'серии побед в лобби нет');
проверить(/ЭкранРейтинга\?\.моёМесто\?\.\('деберц'\)/.test(экран), 'место берётся как у дурака: ЭкранРейтинга.моёМесто(\'деберц\')');
проверить(/карточка-профиля__рейтинг--нет/.test(экран), 'код ставит/снимает класс --нет по наличию места');
проверить(/эл\('лобби-место'\)/.test(экран) && /эл\('лобби-аватар'\)/.test(экран), 'код пишет в «лобби-место» и «лобби-аватар»');
проверить(/освежитьАватар\(\); освежитьМесто\(\);/.test(кусок(экран, 'function меню() {', 'function стол()')), 'место и аватар освежаются на каждом показе лобби');

// 2. Картинка с подписью в общей рамке 16:10.
console.log('\n2. Картинка-гнездо');
const картинка = кусок(html, '<figure class="лобби__картинка">', '</figure>');
проверить(картинка.length > 0, 'figure.лобби__картинка найдена');
const подпись = /<figcaption class="лобби__подпись">([^<]+)<\/figcaption>/.exec(картинка);
проверить(Boolean(подпись) && подпись[1].trim().length > 0, 'у картинки есть подпись figcaption.лобби__подпись' + (подпись ? ' («' + подпись[1].trim() + '»)' : ''));
