let всего = 0;
let провалов = 0;
function проверить(условие, слова) {
  всего++;
  if (условие) console.log('  ок    — ' + слова);
  else { провалов++; console.log('  ПЛОХО — ' + слова); }
  return Boolean(условие);
}

/* ---------- Файловый сервер стенда ---------- */

function поднятьСервер(подмены) {
  const сервер = http.createServer(function (запрос, ответ) {
    let адрес;
    try { адрес = decodeURIComponent(запрос.url.split('?')[0]); } catch (е) { ответ.writeHead(400); ответ.end(); return; }
    if (адрес === '/') адрес = '/монополия.html';
    const относительный = path.normalize(адрес).replace(/^(\.\.[\\/])+/, '').replace(/^[\\/]+/, '');
    const части = относительный.split(/[\\/]/).filter(Boolean);
    if (адрес.toLowerCase().indexOf('.env') !== -1 || (части[0] || '').toLowerCase() === 'bot' ||
        части.some(function (ч) { return ч.charAt(0) === '.'; })) {
      ответ.writeHead(403); ответ.end('закрыто'); return;
    }
    const ключ = относительный.split(path.sep).join('/');
    const файл = подмены[ключ] || path.join(ПРОЕКТ, относительный);
    fs.readFile(файл, function (ошибка, данные) {
      if (ошибка) { ответ.writeHead(404); ответ.end('нет файла'); return; }
      ответ.writeHead(200, { 'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'application/octet-stream', 'Cache-Control': 'no-store' });
      ответ.end(данные);
    });
  });
  return new Promise(function (готово, беда) {
    сервер.once('error', беда);
    сервер.listen(0, '127.0.0.1', function () { готово(сервер); });
  });
}

/* ---------- Один случай ---------- */

/** Партия на двоих; вид строит настоящий видДляИгрока сервера, а не вторая копия полей. */
function новаяПартия() {
  const п = Мон.раздать(null, { игроки: ['м1', 'м2'] });
  п.игра = Правила.create(2, 12345);
  return п;
}
let номерВида = 0;
const видПервого = (п) => Мон.видДляИгрока(п, п.игроки[0], { код: 'ТЕСТ', версия: ++номерВида, сыграноПартий: 0 });

function показатьСтол(в) {
  if (!window.ИграПоСети || typeof window.ИграПоСети.показатьВид !== 'function') return 'нет window.ИграПоСети.показатьВид';
  window.ИграПоСети.показатьВид(в);
  return '';
}

async function случай(браузер, порт, настройка) {
  const страница = await браузер.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
  const ошибки = [];
  страница.on('pageerror', function (е) { ошибки.push(е.message); });
  if (настройка.телеграм) await подготовитьПодделку(страница, { подпись: 'query_id=проверка&user=1' });
  else await безTelegram(страница);
  await страница.goto('http://127.0.0.1:' + порт + '/монополия.html');
  const п = новаяПартия();
  const ош1 = await страница.evaluate(показатьСтол, видПервого(п));
  if (ош1) throw new Error(ош1);
  await страница.waitForTimeout(300);
  // Сдаётся соперник (победа первого) или сам первый (поражение).
  Мон.сделатьХод(п, п.игроки[настройка.ктоСдался], { действие: 'сдаться' });
  const ош2 = await страница.evaluate(показатьСтол, видПервого(п));
  if (ош2) throw new Error(ош2);
  const окно = страница.locator('#mono-modal');
  await окно.waitFor({ state: 'visible', timeout: 5000 });
  return { страница: страница, ошибки: ошибки };
}

async function прогон(подмены) {
  всего = 0; провалов = 0;
  const сервер = await поднятьСервер(подмены);
  const порт = сервер.address().port;
  const браузер = await chromium.launch();
  try {
    const кнопкаВОкне = function (с) { return с.страница.locator('#mono-modal button', { hasText: 'Похвастаться' }); };
    const ещёВОкне = function (с) { return с.страница.locator('#mono-modal button', { hasText: 'Сыграть ещё' }); };

    console.log('Случай 1: победа в Telegram');
    const победа = await случай(браузер, порт, { телеграм: true, ктоСдался: 1 });
    проверить(await ещёВОкне(победа).count() === 1, 'окно итога открыто («Сыграть ещё» есть)');
    проверить(await победа.страница.locator('#mono-modal h2, #mono-modal h3').first().innerText().then(function (т) { return /победил/i.test(т); }).catch(function () { return false; }), 'заголовок говорит о победе');
    проверить(await кнопкаВОкне(победа).count() === 1 && await кнопкаВОкне(победа).isVisible(), 'кнопка «Похвастаться» видна');
    await победа.страница.screenshot({ path: path.join(ПАПКА_СНИМКОВ, 'монополия-похвастаться.png') });

    console.log('Случай 4: нажатие зовёт Сеть.похвастаться');
    const естьДверь = await победа.страница.evaluate(function () { return typeof window.Сеть === 'object' && typeof window.Сеть.похвастаться === 'function'; });
    проверить(естьДверь, 'на странице есть дверь Сеть.похвастаться (js/похвастаться.js подключён)');
    await победа.страница.evaluate(function () {
      window.__хвастовство = [];
      window.Сеть.похвастаться = function (описание) { window.__хвастовство.push(описание); return Promise.resolve({ отправлено: true }); };
    });
    if (await кнопкаВОкне(победа).count() === 1) await кнопкаВОкне(победа).click();
    const звонки = await победа.страница.evaluate(function () { return window.__хвастовство; });
    проверить(звонки.length === 1, 'дверь позвали ровно один раз');
    проверить(звонки.length === 1 && звонки[0].игра === 'монополия' && звонки[0].исход === 'победа', 'описание: игра «монополия», исход «победа»');
    проверить(звонки.length === 1 && звонки[0].игроков === 2 && звонки[0].соперники === 'люди', 'описание: 2 игрока, соперники — люди (партия по сети)');
    проверить(победа.ошибки.length === 0, 'ошибок страницы нет' + (победа.ошибки.length ? ': ' + победа.ошибки[0] : ''));
    await победа.страница.close();

    console.log('Случай 2: победа без Telegram');
    const безТГ = await случай(браузер, порт, { телеграм: false, ктоСдался: 1 });
    проверить(await ещёВОкне(безТГ).count() === 1, 'окно итога открыто («Сыграть ещё» есть)');
    проверить(await кнопкаВОкне(безТГ).count() === 0, 'кнопки «Похвастаться» нет');
    await безТГ.страница.close();

    console.log('Случай 3: поражение в Telegram');
    const поражение = await случай(браузер, порт, { телеграм: true, ктоСдался: 0 });
    проверить(await ещёВОкне(поражение).count() === 1, 'окно итога открыто («Сыграть ещё» есть)');
    проверить(await кнопкаВОкне(поражение).count() === 0, 'кнопки «Похвастаться» нет');
    await поражение.страница.close();
  } finally {
    await браузер.close();
    сервер.close();
  }
  return провалов;
}

/* ---------- Ломающий прогон ---------- */

async function сломать() {
  console.log('Контрольный прогон по целой копии (обязан быть зелёным)');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'хвастовство-'));
  const копия = path.join(папка, 'монополия-экран.js');
  const исходник = fs.readFileSync(path.join(ПРОЕКТ, ИМЯ_ЭКРАНА), 'utf8');
  fs.writeFileSync(копия, исходник);
  const контроль = await прогон({ [ИМЯ_ЭКРАНА]: копия });
  проверить(true, 'контрольный прогон завершён');
  const условие = 'v.winner === v.me &&\n      !этоСогласие &&\n      внутриTelegram()';
  const сколько = исходник.split(условие).length - 1;
  if (сколько !== 1) { console.log('ПЛОХО — строка порчи найдена ' + сколько + ' раз, нужно ровно 1'); process.exit(1); }
  fs.writeFileSync(копия, исходник.replace(условие, '!этоСогласие &&\n      внутриTelegram()'));
  console.log('\nЛомающий прогон: копия без условия «победа» (обязан покраснеть)');
  const сломанный = await прогон({ [ИМЯ_ЭКРАНА]: копия });
  console.log('\nКонтроль: провалов ' + контроль + ' (нужно 0); сломанная копия: провалов ' + сломанный + ' (нужно больше 0)');
  fs.rmSync(папка, { recursive: true, force: true });
  process.exit(контроль === 0 && сломанный > 0 ? 0 : 1);
}

(async function () {
  if (process.argv.includes('--сломать')) return сломать();
  const красных = await прогон({});
  console.log('\nИтого проверок: ' + всего + ', провалов: ' + красных);
  process.exit(красных ? 1 : 0);
})().catch(function (е) { console.log('Проверка упала: ' + (е && е.stack || е)); process.exit(1); });
