'use strict';

/* =====================================================================
   Напарник, который играет ЧЕРЕЗ ТУННЕЛЬ (адрес https://...trycloudflare.com).

   Зачем отдельно от tests/сетевой-автопрогон.js: тот стучится напрямую
   на 127.0.0.1 и туннель не трогает вовсе. А жалоба владельца — именно
   про игру по ссылке из интернета, где между браузером и сервером стоит
   Cloudflare. Здесь всё идёт длинным путём: интернет, туннель, сервер.

   Два режима:

     1) Оба игрока — программа. Проверяет туннель целиком, без браузера:
            node tests/напарник-через-туннель.js авто https://адрес 3

     2) Напарник живому человеку. Человек создал игру в браузере и
        продиктовал код — программа входит по этому коду и играет
        за второго, пока человек кладёт карты пальцем:
            node tests/напарник-через-туннель.js войти https://адрес КОД

   Ничего не гасит и ничего не чинит: только играет и рассказывает.
   ===================================================================== */

const https = require('https');
const http = require('http');
const { URL } = require('url');

const РЕЖИМ = process.argv[2] || 'авто';
const АДРЕС = (process.argv[3] || '').replace(/\/+$/, '');
const ТРЕТИЙ = process.argv[4] || '';

if (!АДРЕС) {
  console.log('Не сказали адрес сервера. Пример:');
  console.log('  node tests/напарник-через-туннель.js авто https://пример.trycloudflare.com 3');
  console.log('  node tests/напарник-через-туннель.js войти https://пример.trycloudflare.com AB12');
  process.exit(1);
}

/* Больше этого числа действий партия длиться не может: 36 карт, у каждой
   конечное число превращений. Упёрлись в потолок — значит игра зависла. */
const ПОТОЛОК_ДЕЙСТВИЙ = 800;

const провалы = [];
let проверок = 0;
/* Сколько времени занял самый долгий запрос — так видно, тормозит ли туннель. */
let самыйДолгийЗапросМс = 0;
let всегоЗапросов = 0;

function проверить(условие, что) {
  проверок++;
  if (!условие) провалы.push(что);
}

/* ---------------------------------------------------------------------
   Разговор с сервером через туннель
   --------------------------------------------------------------------- */

/** Один POST-запрос по настоящему адресу. Возвращает { номер, данные, мс }. */
function запрос(путь, тело, сколькоЖдатьМс) {
  return new Promise(function (готово, беда) {
    const начало = Date.now();
    const цель = new URL(АДРЕС + encodeURI(путь));
    const транспорт = цель.protocol === 'https:' ? https : http;
    const текст = Buffer.from(JSON.stringify(тело || {}), 'utf8');

    const обращение = транспорт.request({
      protocol: цель.protocol,
      hostname: цель.hostname,
      port: цель.port || (цель.protocol === 'https:' ? 443 : 80),
      path: цель.pathname + цель.search,
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Content-Length': текст.length,
        // Представляемся так же, как браузер игрока: адрес опубликованной игры.
        'Origin': 'https://aleustim-boop.github.io'
      }
    }, function (ответ) {
      let куски = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (к) { куски += к; });
      ответ.on('end', function () {
        const мс = Date.now() - начало;
        всегоЗапросов++;
        if (мс > самыйДолгийЗапросМс) самыйДолгийЗапросМс = мс;
        let данные = {};
        try {
          данные = JSON.parse(куски);
        } catch (сбой) {
          // Вот здесь и вылезла бы заглушка Cloudflare «вы человек?»:
          // вместо ответа сервера пришла бы страница HTML.
          данные = { сыройОтвет: куски.slice(0, 400), этоНеJSON: true };
        }
        готово({ номер: ответ.statusCode, данные: данные, мс: мс });
      });
    });

    обращение.setTimeout(сколькоЖдатьМс || 20000, function () {
      обращение.destroy(new Error('сервер не ответил на ' + путь + ' за ' +
        ((сколькоЖдатьМс || 20000) / 1000) + ' секунд'));
    });
    обращение.on('error', беда);
    обращение.end(текст);
  });
}

/** Проверка «сервер жив» обычным GET — как если открыть адрес в браузере. */
function здоровье() {
  return new Promise(function (готово, беда) {
    const цель = new URL(АДРЕС + encodeURI('/здоровье'));
    const транспорт = цель.protocol === 'https:' ? https : http;
    транспорт.get({
      protocol: цель.protocol, hostname: цель.hostname,
      port: цель.port || (цель.protocol === 'https:' ? 443 : 80),
      path: цель.pathname
    }, function (ответ) {
      let к = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (ч) { к += ч; });
      ответ.on('end', function () {
        try {
          готово({ номер: ответ.statusCode, данные: JSON.parse(к) });
        } catch (сбой) {
          беда(new Error('сервер ответил не ответом, а вот этим: ' + к.slice(0, 300)));
        }
      });
    }).on('error', беда);
  });
}

/* ---------------------------------------------------------------------
   Один игрок
   --------------------------------------------------------------------- */

class Игрок {
  constructor(имя, код, пропуск, состояние) {
    this.имя = имя;
    this.код = код;
    this.пропуск = пропуск;
    this.вид = состояние || null;
  }

  async обновить() {
    const о = await запрос('/состояние', { код: this.код, пропуск: this.пропуск });
    проверить(о.номер === 200, this.имя + ': сервер не отдал состояние (' + о.номер + ')');
    if (о.данные.состояние) this.вид = о.данные.состояние;
    return this.вид;
  }

  async ход(намерение) {
    const о = await запрос('/ход',
      Object.assign({ код: this.код, пропуск: this.пропуск }, намерение));
    проверить(о.номер === 200, this.имя + ': сервер ответил на ход кодом ' + о.номер);
    if (о.данные.состояние) this.вид = о.данные.состояние;
    return о.данные;
  }

  чтоНового(версия, сколькоЖдать) {
    return запрос('/что-нового',
      { код: this.код, пропуск: this.пропуск, версия: версия }, сколькоЖдать || 40000);
  }

  выйти() {
    return запрос('/выйти', { код: this.код, пропуск: this.пропуск });
  }
}

/** Один осмысленный ход: перебираем карты, как человек пальцем. */
async function походить(игрок) {
  const вид = игрок.вид;
  if (!вид || вид.завершена) return false;
  if (!вид.яХожу) return false;

  if (вид.фаза === 'защита') {
    for (let пара = 0; пара < вид.стол.length; пара++) {
      if (вид.стол[пара].защита) continue;
      for (let карта = 0; карта < вид.мояРука.length; карта++) {
        const ответ = await игрок.ход({ действие: 'отбить', пара: пара, карта: карта });
        if (ответ.принято) return true;
      }
    }
    const беру = await игрок.ход({ действие: 'беру' });
    проверить(беру.принято,
      игрок.имя + ': отбиться не смог и «Беру» тоже не приняли — ' + беру.причина);
    return беру.принято;
  }

  for (let карта = 0; карта < вид.мояРука.length; карта++) {
    const ответ = await игрок.ход({ действие: 'ходить', карта: карта });
    if (ответ.принято) return true;
  }
  const бито = await игрок.ход({ действие: 'бито' });
  if (бито.принято) return true;

  проверить(false, игрок.имя + ': ходить нечем и подход не закрыть — «' + бито.причина +
    '» (фаза ' + вид.фаза + ', карт в руке ' + вид.мояРука.length + ')');
  return false;
}

/* ---------------------------------------------------------------------
   Режим 1: оба игрока — программа, всё через туннель
   --------------------------------------------------------------------- */

async function сыгратьКомнату(номер) {
  const создание = await запрос('/создать', {});
  проверить(создание.номер === 200 && создание.данные.код,
    'комната ' + номер + ': сервер не создал игру (код ответа ' + создание.номер + ')');
  if (!создание.данные.код) return null;

  const первый = new Игрок('комната ' + номер + ', первый',
    создание.данные.код, создание.данные.пропуск, создание.данные.состояние);

  const вход = await запрос('/войти', { код: создание.данные.код });
  проверить(вход.номер === 200 && вход.данные.пропуск,
    'комната ' + номер + ': друг не смог войти по коду');
  if (!вход.данные.пропуск) return null;

  const второй = new Игрок('комната ' + номер + ', второй',
    вход.данные.код, вход.данные.пропуск, вход.данные.состояние);

  await первый.обновить();
  await второй.обновить();

  let действий = 0;
  let сделаноЗаКруг = 1;
  while (!(первый.вид && первый.вид.завершена) &&
         действий < ПОТОЛОК_ДЕЙСТВИЙ && сделаноЗаКруг > 0) {
    сделаноЗаКруг = 0;
    for (const игрок of [первый, второй]) {
      await игрок.обновить();
      if (await походить(игрок)) сделаноЗаКруг++;
      действий++;
    }
  }

  проверить(действий < ПОТОЛОК_ДЕЙСТВИЙ,
    'комната ' + номер + ': партия не кончилась за ' + ПОТОЛОК_ДЕЙСТВИЙ +
    ' действий — похоже на зависание');
  проверить(Boolean(первый.вид && первый.вид.завершена) &&
            Boolean(второй.вид && второй.вид.завершена),
    'комната ' + номер + ': партия кончилась не у обоих сразу');

  const итоги = [первый.вид.итог, второй.вид.итог].sort().join('+');
  проверить(итоги === 'победа+поражение' || итоги === 'ничья+ничья',
    'комната ' + номер + ': итоги не зеркальные — ' + итоги);

  await первый.выйти();
  await второй.выйти();
  return { код: создание.данные.код, действий: действий, итоги: итоги };
}

/* ---------------------------------------------------------------------
   Режим 2: напарник живому человеку в браузере
   --------------------------------------------------------------------- */

async function войтиКЧеловеку(код) {
  console.log('Вхожу по коду ' + код + ' через ' + АДРЕС);
  const вход = await запрос('/войти', { код: код });
  if (вход.номер !== 200 || !вход.данные.пропуск) {
    console.log('Войти не удалось. Код ответа ' + вход.номер +
      ', сервер сказал: ' + JSON.stringify(вход.данные).slice(0, 300));
    return;
  }
  console.log('Вошёл. Играю за второго, жду ходов человека.');

  const я = new Игрок('напарник', вход.данные.код, вход.данные.пропуск, вход.данные.состояние);
  let действий = 0;
  let тишины = 0;

  while (действий < ПОТОЛОК_ДЕЙСТВИЙ && тишины < 40) {
    await я.обновить();
    if (!я.вид) break;

    if (я.вид.завершена) {
      console.log('Партия закончилась. Мой итог: ' + я.вид.итог);
      break;
    }
    if (я.вид.соперникУшёл) {
      console.log('Человек вышел из игры.');
      break;
    }

    if (я.вид.яХожу) {
      const получилось = await походить(я);
      действий++;
      тишины = 0;
      console.log('Походил (' + действий + '). Фаза: ' + я.вид.фаза +
        ', карт у меня ' + (я.вид.мояРука ? я.вид.мояРука.length : '?') +
        ', у человека ' + я.вид.картУСоперника +
        (получилось ? '' : ' — ход не приняли!'));
    } else {
      // Ждём хода человека длинным опросом — ровно как браузер.
      // Сервер держит соединение 25 секунд, поэтому ждём 40, как настоящая игра.
      // Если не дождались — это не поломка, просто человек задумался.
      let новость = null;
      try {
        новость = await я.чтоНового(я.вид.версия, 40000);
      } catch (сбой) {
        console.log('Опрос оборвался: ' + сбой.message);
      }
      if (новость && новость.данные && новость.данные.изменилось) {
        if (новость.данные.состояние) я.вид = новость.данные.состояние;
        тишины = 0;
      } else {
        тишины++;
        console.log('Жду хода человека… (' + тишины + ')');
      }
    }
  }

  await я.выйти();
  console.log('Вышел из комнаты.');
}

/* ---------------------------------------------------------------------
   Запуск
   --------------------------------------------------------------------- */

(async function () {
  console.log('Сервер: ' + АДРЕС);
  try {
    const здор = await здоровье();
    console.log('Проверка «жив ли сервер»: код ' + здор.номер + ', ответ ' +
      JSON.stringify(здор.данные));
  } catch (сбой) {
    console.log('ОСЕЧКА на проверке здоровья: ' + сбой.message);
    process.exit(1);
  }

  if (РЕЖИМ === 'войти') {
    if (!ТРЕТИЙ) { console.log('Не сказали код комнаты.'); process.exit(1); }
    await войтиКЧеловеку(ТРЕТИЙ.toUpperCase());
    return;
  }

  const сколько = Number(ТРЕТИЙ) || 3;
  console.log('Играю ' + сколько + ' полных партий вдвоём через туннель…\n');
  const начало = Date.now();

  for (let i = 1; i <= сколько; i++) {
    try {
      const итог = await сыгратьКомнату(i);
      if (итог) {
        console.log('Комната ' + i + ' (' + итог.код + '): доиграна за ' +
          итог.действий + ' действий, итог ' + итог.итоги);
      } else {
        console.log('Комната ' + i + ': сыграть не удалось.');
      }
    } catch (сбой) {
      провалы.push('комната ' + i + ': сорвалось — ' + сбой.message);
      console.log('Комната ' + i + ': СОРВАЛОСЬ — ' + сбой.message);
    }
  }

  const секунд = ((Date.now() - начало) / 1000).toFixed(1);
  console.log('\n----- ИТОГ -----');
  console.log('Партий: ' + сколько + ', проверок: ' + проверок + ', за ' + секунд + ' сек');
  console.log('Запросов через туннель: ' + всегоЗапросов +
    ', самый долгий ответ: ' + самыйДолгийЗапросМс + ' мс');
  if (провалы.length === 0) {
    console.log('Поломок не нашёл: игра вдвоём через туннель работает целиком.');
  } else {
    console.log('НАШЁЛ ПОЛОМКИ (' + провалы.length + '):');
    провалы.slice(0, 30).forEach(function (п, i) { console.log('  ' + (i + 1) + ') ' + п); });
    process.exitCode = 1;
  }
})();
