/* =====================================================================
   ЗАМЕР СИЛЫ УРОВНЕЙ ШАШЕЧНОГО БОТА.

   Зачем. Названия уровней — обещание игроку. Сейчас они держатся на слове:
   настоящего замера у шашек не было, и мы не знаем, правда ли «сложный»
   сильнее «обычного».

   Как меряем — по урокам нард:
     · общие исходные позиции: разброс задают первые ходы, выбранные по
       зерну; одна и та же позиция играется ДВАЖДЫ, со сменой цвета;
     · лестница целиком: не только сложный против обычного, но и каждый
       уровень против случайного игрока. Уровень, который еле обыгрывает
       случайные ходы, не думает, а делает вид;
     · погрешность называем вслух. Перевес, который уже́ погрешности,
       ничего не доказывает.

   Очки: победа 2, ничья 1, поражение 0 — как в замере дурака. Итог
   приводится к «из 100».

   Бюджет времени — серверный (150 мс на сложном): именно так бот играет
   по сети. В браузере против человека у него 300 мс, то есть чуть сильнее.

   Запуск: node tests/замер-шашек.js [партий на пару]   (по умолчанию 100)

   Прогон долгий: полный занимает около шести минут. Машину под него
   стоит освободить — в нардах загруженная машина искажала числа.
   ===================================================================== */

const path = require('path');
const КОРЕНЬ = path.join(__dirname, '..');
const Правила = require(path.join(КОРЕНЬ, 'js', 'шашки-правила.js'));
const Бот = require(path.join(КОРЕНЬ, 'js', 'шашки-бот.js'));

const БЮДЖЕТ_СЛОЖНОГО = 150;
const ПОТОЛОК_ХОДОВ = 200;

/* Повторимая случайность: один и тот же прогон даёт одни и те же партии,
   и спорный результат можно переиграть в точности. */
function зерно(начало) {
  let х = начало >>> 0;
  return function () {
    х ^= х << 13; х >>>= 0;
    х ^= х >> 17;
    х ^= х << 5; х >>>= 0;
    return х / 4294967296;
  };
}

/** Игрок: уровень бота или «случайный». */
function ходИгрока(партия, кто, случайное) {
  const ходы = Правила.возможныеХоды(партия);
  if (!ходы.length) return null;
  if (кто === 'случайный') return ходы[Math.floor(случайное() * ходы.length)];
  return Бот.выбратьХодСразу(партия, {
    уровень: кто,
    бюджетМс: кто === 'сложный' ? БЮДЖЕТ_СЛОЖНОГО : 0,
    случайное: случайное
  });
}

/** Одна партия. Возвращает 'белые', 'чёрные' или 'ничья'. */
function партия(белые, чёрные, первыеХоды, случайное) {
  const п = Правила.создатьПартию();
  // Общая исходная: несколько случайных ходов, одинаковых для обеих сторон пары.
  for (const шаг of первыеХоды) {
    const ходы = Правила.возможныеХоды(п);
    if (!ходы.length) break;
    Правила.сделатьХод(п, ходы[шаг % ходы.length]);
  }
  let ходов = 0;
  while (!Правила.партияЗавершена(п) && ходов < ПОТОЛОК_ХОДОВ) {
    const чей = Правила.чейХод(п) === Правила.БЕЛЫЕ ? белые : чёрные;
    const ход = ходИгрока(п, чей, случайное);
    if (!ход) break;
    Правила.сделатьХод(п, ход);
    ходов++;
  }
  const итог = Правила.итог(п);
  if (!итог) return 'ничья';          // упёрлись в потолок — считаем ничьей
  return итог.ничья ? 'ничья' : итог.победитель;
}

/** Пара уровней: N партий, каждая позиция дважды со сменой цвета. */
function пара(испытуемый, соперник, партий) {
  const случайное = зерно(20260909);
  let очки = 0, побед = 0, ничьих = 0, поражений = 0;
  const начало = Date.now();

  for (let номер = 0; номер < партий; номер++) {
    // Общая исходная — одна на два цвета: первые два хода по зерну.
    const первые = [Math.floor(случайное() * 7), Math.floor(случайное() * 7)];
    const испытуемыйБелыми = номер % 2 === 0;
    const итог = испытуемыйБелыми
      ? партия(испытуемый, соперник, первые, случайное)
      : партия(соперник, испытуемый, первые, случайное);

    const выиграл = итог !== 'ничья' &&
      ((испытуемыйБелыми && итог === Правила.БЕЛЫЕ) ||
       (!испытуемыйБелыми && итог === Правила.ЧЁРНЫЕ));
    if (итог === 'ничья') { очки += 1; ничьих++; }
    else if (выиграл) { очки += 2; побед++; }
    else поражений++;
  }

  const доля = очки / (2 * партий);
  const изСта = доля * 100;
  /* Случайная ошибка: девяносто пять процентов доверия. Перевес, который
     уже этой полосы, ничего не доказывает — так было в нардах. */
  const погрешность = 1.96 * Math.sqrt(доля * (1 - доля) / партий) * 100;
  return {
    изСта: изСта, погрешность: погрешность,
    побед: побед, ничьих: ничьих, поражений: поражений,
    секунд: Math.round((Date.now() - начало) / 1000)
  };
}

const ПАРТИЙ = Number(process.argv[2]) || 100;

console.log('=== Замер силы уровней шашечного бота ===');
console.log('партий на пару: ' + ПАРТИЙ + ', бюджет сложного: ' + БЮДЖЕТ_СЛОЖНОГО + ' мс');
console.log('очки: победа 2, ничья 1; каждая позиция играется дважды, со сменой цвета\n');

const лестница = [
  ['лёгкий', 'случайный', ПАРТИЙ],
  ['обычный', 'случайный', ПАРТИЙ],
  ['обычный', 'лёгкий', ПАРТИЙ],
  ['сложный', 'случайный', Math.max(30, Math.round(ПАРТИЙ * 0.4))],
  ['сложный', 'обычный', Math.max(40, Math.round(ПАРТИЙ * 0.6))]
];

const итоги = [];
for (const [кто, против, сколько] of лестница) {
  const р = пара(кто, против, сколько);
  итоги.push({ кто, против, сколько, ...р });
  console.log(кто + ' против «' + против + '»: ' +
    р.изСта.toFixed(1) + ' из 100 (±' + р.погрешность.toFixed(1) + ')' +
    '  [+' + р.побед + ' =' + р.ничьих + ' -' + р.поражений + ', ' +
    сколько + ' партий, ' + р.секунд + ' с]');
}

console.log('\n--- Что это значит ---');
for (const и of итоги) {
  const перевесДоказан = и.изСта - и.погрешность > 50;
  const слабостьДоказана = и.изСта + и.погрешность < 50;
  console.log(и.кто + ' против «' + и.против + '»: ' +
    (перевесДоказан ? 'перевес ДОКАЗАН'
     : слабостьДоказана ? 'ХУЖЕ соперника'
     : 'перевес НЕ доказан — он уже погрешности'));
}
