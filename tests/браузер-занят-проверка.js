'use strict';

/* =====================================================================
   ПРОВЕРКА ДЛЯ штаб/браузер-занят.js — считает ли программа занятостью
   именно браузеры проверок, а не всё подряд.

   Беда была двойная. Во-первых, программа считала занятым любой node.exe
   с «tests/» в командной строке — из-за этого сетевые проверки без
   браузера вовсе держали исполнителей в очереди по 40 минут впустую.
   Во-вторых, владелец разрешил гонять по несколько браузеров разом —
   очередь «один и только один» устарела, нужен предел по числу и по
   свободной памяти.

   Проверка не трогает настоящий PowerShell и настоящую машину: решение
   «занято/свободно» вынесено в программе в чистые функции
   (отфильтроватьГлавныеБраузеры, решить), сюда подаются поддельные
   списки процессов и поддельные числа свободной памяти.

   ЗАПУСК
       node tests/браузер-занят-проверка.js
           — обычный прогон: чистые функции настоящего
             штаб/браузер-занят.js на семи наборах данных.

       node tests/браузер-занят-проверка.js <путь-к-файлу>
           — тот же набор проверок, но над другим файлом браузер-занят.js
             (используется ломающим прогоном, путь — к копии).

       node tests/браузер-занят-проверка.js --сломать
           — ломающий: делает во временной папке испорченную копию
             штаб/браузер-занят.js (предел браузеров задран до 9999),
             прогоняет над ней те же семь наборов данных ЭТИМ ЖЕ файлом
             (путь к копии передаётся доводом) и требует, чтобы прогон
             над копией покраснел. Настоящий штаб/браузер-занят.js при
             этом не трогается — портится только временная копия.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const НАСТОЯЩИЙ_ФАЙЛ = path.join(КОРЕНЬ, 'штаб', 'браузер-занят.js');

/* Довод-путь к копии для ломающего прогона, если он есть; иначе — настоящий файл. */
const первыйДовод = process.argv[2];
const проверяемыйФайл = (первыйДовод && !первыйДовод.startsWith('--')) ? первыйДовод : НАСТОЯЩИЙ_ФАЙЛ;

function запуститьОбычныйПрогон() {
  const программа = require(проверяемыйФайл);

  let проверок = 0;
  const провалы = [];
  function проверить(условие, что) {
    проверок++;
    if (условие) {
      console.log('  ок   ' + что);
      return;
    }
    провалы.push(что);
    console.log('  ПРОВАЛ: ' + что);
  }

  console.log('Проверяю файл: ' + проверяемыйФайл);

  /* Поддельный «главный» процесс браузера проверки: chrome.exe, --headless,
     без --type= — то, что и должно считаться занятостью. */
  function браузерыПроверок(сколько) {
    const список = [];
    for (let i = 0; i < сколько; i++) {
      список.push({
        Name: 'chrome.exe',
        ProcessId: 1000 + i,
        CommandLine: 'C:\\Program Files\\...\\ms-playwright\\chromium-1091\\chrome-win\\chrome.exe' +
          ' --headless --disable-gpu --remote-debugging-port=' + (9000 + i),
      });
    }
    return список;
  }

  // 1. Пусто — свободно.
  {
    const итог = программа.решить(программа.отфильтроватьГлавныеБраузеры([]), 8000);
    проверить(итог.занято === false, 'пустой список процессов — свободно');
    проверить(итог.число === 0, 'браузеров найдено ноль');
  }

  // 2. Два браузера при большой памяти — свободно (предел — 3).
  {
    const итог = программа.решить(программа.отфильтроватьГлавныеБраузеры(браузерыПроверок(2)), 8000);
    проверить(итог.занято === false, 'два браузера проверок при большой памяти — свободно');
    проверить(итог.число === 2, 'найдено ровно два браузера');
  }

  // 3. Три браузера — уже занято.
  {
    const итог = программа.решить(программа.отфильтроватьГлавныеБраузеры(браузерыПроверок(3)), 8000);
    проверить(итог.занято === true, 'три браузера проверок при большой памяти — занято');
    проверить(итог.число === 3, 'найдено ровно три браузера');
  }

  // 4. Обычный Chrome владельца, без --headless и без ms-playwright — не считается.
  {
    const обычныйChrome = [{
      Name: 'chrome.exe',
      ProcessId: 5000,
      CommandLine: '"C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe" --profile-directory=Default',
    }];
    const главные = программа.отфильтроватьГлавныеБраузеры(обычныйChrome);
    проверить(главные.length === 0, 'обычный Chrome владельца без headless/ms-playwright не считается проверкой');
  }

  // 5. Дочерние процессы (--type=renderer, --type=gpu-process) — не считаются отдельно.
  {
    const сДочерними = браузерыПроверок(1).concat([
      {
        Name: 'chrome.exe',
        ProcessId: 6001,
        CommandLine: 'C:\\...\\ms-playwright\\chromium-1091\\chrome-win\\chrome.exe --type=renderer --headless --field-trial-handle=1',
      },
      {
        Name: 'chrome.exe',
        ProcessId: 6002,
        CommandLine: 'C:\\...\\ms-playwright\\chromium-1091\\chrome-win\\chrome.exe --type=gpu-process --headless',
      },
    ]);
    const главные = программа.отфильтроватьГлавныеБраузеры(сДочерними);
    проверить(главные.length === 1, 'дочерние процессы браузера (--type=) не считаются отдельными браузерами');
  }

  // 6. Память меньше 3 ГБ — занято даже при одном браузере.
  {
    const итог = программа.решить(программа.отфильтроватьГлавныеБраузеры(браузерыПроверок(1)), 2048);
    проверить(итог.занято === true, 'свободной памяти 2 ГБ — занято, даже при одном браузере');
    проверить(/памят/.test(итог.причина || ''), 'причина занятости названа словами про память');
  }

  // 7. node-скрипт из tests (сетевая проверка без браузера) — вообще не браузер, игнорируется полностью.
  {
    const сNode = [{
      Name: 'node.exe',
      ProcessId: 7000,
      CommandLine: 'node.exe D:\\Claud\\Games\\tests\\злые-запросы-о-приглашении.js --headless',
    }];
    const главные = программа.отфильтроватьГлавныеБраузеры(сNode);
    проверить(главные.length === 0, 'node-скрипт из tests не считается браузером проверки, даже если в его доводах есть слово --headless');
  }

  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалы.length);
  return провалы.length === 0;
}

/* Испорченная копия во временной папке: предел браузеров задран до 9999,
   поэтому набор «три браузера — занято» перестаёт работать. Настоящий
   файл проекта не трогаем ни на секунду. */
function собратьИспорченнуюКопию() {
  const текст = fs.readFileSync(НАСТОЯЩИЙ_ФАЙЛ, 'utf8');
  const меткаПоиска = /const ПРЕДЕЛ_БРАУЗЕРОВ = \d+;/;
  if (!меткаПоиска.test(текст)) {
    throw new Error('в штаб/браузер-занят.js не нашлась константа ПРЕДЕЛ_БРАУЗЕРОВ — проверка устарела, ломать нечего');
  }
  const испорченный = текст.replace(меткаПоиска,
    'const ПРЕДЕЛ_БРАУЗЕРОВ = 9999; // ИСПОРЧЕНО ломающим прогоном tests/браузер-занят-проверка.js, в настоящем файле такого нет');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'браузер-занят-испорчен-'));
  const путь = path.join(папка, 'браузер-занят.js');
  fs.writeFileSync(путь, испорченный, 'utf8');
  return путь;
}

function запуститьЛомающийПрогон() {
  const путьККопии = собратьИспорченнуюКопию();
  console.log('Ломающий прогон: копия с задранным пределом браузеров -> ' + путьККопии);

  let проверкаУпала = false;
  let вывод = '';
  try {
    вывод = execFileSync(process.execPath, [__filename, путьККопии], { encoding: 'utf8' });
  } catch (ошибка) {
    проверкаУпала = true;
    вывод = (ошибка.stdout || '') + (ошибка.stderr || '');
  }
  console.log(вывод.trim());

  try {
    fs.unlinkSync(путьККопии);
    fs.rmdirSync(path.dirname(путьККопии));
  } catch (е) { /* временная папка не критична, но чистим за собой */ }

  if (проверкаУпала) {
    console.log('Проверка на испорченной копии ПОКРАСНЕЛА, как и должна — ломающий прогон подтверждён.');
    return true;
  }
  console.log('ПРОВАЛ ломающего прогона: испорченная копия с пределом 9999 не поймана, проверка осталась зелёной.');
  return false;
}

if (process.argv.includes('--сломать')) {
  process.exit(запуститьЛомающийПрогон() ? 0 : 1);
} else {
  process.exit(запуститьОбычныйПрогон() ? 0 : 1);
}
