/* =====================================================================
   СТРАЖ: ДЕБЕРЦ, ШАХМАТЫ И МОРСКОЙ БОЙ БЕРУТ СЛУЧАЙНОСТЬ ИЗ NODE:CRYPTO

   Что проверяем. Разработчик перевёл три места на сервере с предсказуемого
   Math.random на node:crypto.randomInt — так же, как раньше сделали в
   нардах (образец — server/игры/нарды.js:85–87, страж-образец —
   tests/нарды-кости-из-crypto.js, устройство этого файла повторяет его):

     1) server/игры/деберц.js — функция-помощник «случайность()» наверху
        файла (crypto.randomInt(0, 2**48) / 2**48), её передают в
        П.создать(...) внутри «раздать» и в Б.карта(...) внутри
        «ходЗаБота» вместо Math.random.
     2) server/игры/шахматы.js — в «раздать» жребий цвета:
        все[require('node:crypto').randomInt(все.length)].
     3) server/игры/морской-бой.js — в «раздать» жребий первого хода:
        require('node:crypto').randomInt(2).

   Math.random предсказуем (по паре подсмотренных чисел его состояние
   восстанавливается) — читер угадал бы тасовку колоды деберца, цвет
   в шахматах или кто ходит первым в морском бою. node:crypto.randomInt
   так не разгадать.

   В файлах остались упоминания «Math.random» только в комментариях
   (объясняют, почему от него ушли) — этот страж вырезает блочные и
   строчные комментарии перед поиском, иначе он покраснел бы на честном
   файле.

   Как проверяем.
     А) СТРАЖ ПО ИСХОДНИКУ (всегда, для каждого из трёх файлов): читаем
        текст, вырезаем комментарии, находим нужные функции по имени
        (в деберце — «случайность», «раздать», «ходЗаБота»; в шахматах
        и морском бое — «раздать»). Не нашли функцию — это ПРОВАЛ, а не
        пропуск (правило проекта «ноль найденного — провал»). Дальше
        проверяем: в файле есть node:crypto (или crypto) и randomInt,
        в теле каждой найденной функции нет Math.random, и во всём коде
        файла без комментариев тоже нигде нет Math.random.
     Б) ПОВЕДЕНИЕ (только когда путь к копии не передан, то есть
        проверяем настоящие файлы проекта, а не ломающую копию без
        соседних require'ов):
          - деберц: раздать(null, { игроки: [1, 2] }) 30 раз, смотрим
            первую карту руки первого игрока (игра.руки[0][0].id, поле
            «руки» — см. игры/деберц/деберц-правила.js) — должно встретиться хотя
            бы 3 разных значения;
          - морской бой: раздать(null, { игроки: [1, 2] }) 200 раз,
            смотрим игра.первый (игры/морской-бой/морской-бой-правила.js, создать) —
            должны встретиться оба значения, 0 и 1;
          - шахматы: раздать(null, { игроки: ['a', 'b'] }) 200 раз,
            смотрим партия.цвета['a'] и партия.цвета['b'] — оба места
            должны хоть раз побывать белыми («ктоНачинает» не входит
            в список игроков — сервер обязан бросить жребий).

   Запуск (файлы проекта):
     node tests/сервер-случайность-из-crypto.js

   Ломающий запуск (путь к папке с испорченными копиями трёх файлов —
   поведение на копиях не проверяется, они лежат без соседних require'ов
   и корректно не подключились бы):
     node tests/сервер-случайность-из-crypto.js ПУТЬ_К_ПАПКЕ_С_КОПИЯМИ
   ===================================================================== */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');

const ФАЙЛЫ = [
  { имя: 'деберц.js', путьПоУмолчанию: path.join(КОРЕНЬ, 'server', 'игры', 'деберц.js'), функции: ['случайность', 'раздать', 'ходЗаБота'] },
  { имя: 'шахматы.js', путьПоУмолчанию: path.join(КОРЕНЬ, 'server', 'игры', 'шахматы.js'), функции: ['раздать'] },
  { имя: 'морской-бой.js', путьПоУмолчанию: path.join(КОРЕНЬ, 'server', 'игры', 'морской-бой.js'), функции: ['раздать'] }
];

const путьДовод = process.argv[2];
const этоЛомающийЗапуск = Boolean(путьДовод);

let проверок = 0;
let ошибок = 0;

function шаг(ок, текст) {
  проверок++;
  if (!ок) ошибок++;
  console.log((ок ? 'ок' : 'ПЛОХО') + ' — ' + текст);
}

/** Убрать /* … *\/ и // … — комментарии не должны участвовать в поиске Math.random. */
function убратьКомментарии(текст) {
  let без = текст.replace(/\/\*[\s\S]*?\*\//g, '');
  без = без.replace(/\/\/[^\n]*/g, '');
  return без;
}

/**
 * Найти тело function ИМЯ(...) { ... } балансировкой скобок — функции
 * «раздать» и «ходЗаБота» многострочные, с вложенными { } внутри
 * (объекты, if/else), однострочный поиск «до первой }» их бы обрезал.
 * Не нашли — null (это провал у вызывающего кода, не пропуск).
 */
function извлечьТелоФункции(текст, имя) {
  const регИмени = new RegExp('function\\s+' + имя + '\\s*\\(');
  const совпадение = регИмени.exec(текст);
  if (!совпадение) return null;

  let i = совпадение.index + совпадение[0].length - 1; // стоим на открывающей '(' параметров
  let глубинаКруглых = 0;
  for (; i < текст.length; i++) {
    if (текст[i] === '(') глубинаКруглых++;
    else if (текст[i] === ')') { глубинаКруглых--; if (глубинаКруглых === 0) { i++; break; } }
  }
  while (i < текст.length && текст[i] !== '{') i++;
  if (текст[i] !== '{') return null;

  const начало = i;
  let глубинаФигур = 0;
  for (; i < текст.length; i++) {
    if (текст[i] === '{') глубинаФигур++;
    else if (текст[i] === '}') { глубинаФигур--; if (глубинаФигур === 0) { i++; break; } }
  }
  if (глубинаФигур !== 0) return null; // скобки не сошлись — считаем, что не нашли
  return текст.slice(начало, i);
}

console.log('=== Страж: случайность деберца, шахмат и морского боя берётся из node:crypto ===');
console.log(этоЛомающийЗапуск ? ('Папка с копиями: ' + path.resolve(путьДовод) + ' (ломающий запуск)') : 'Файлы проекта (обычный запуск)');
console.log('');

const найденныеМодули = {}; // имя файла -> { путь, текст, текстБезКомментариев }

for (const файл of ФАЙЛЫ) {
  const путь = этоЛомающийЗапуск ? path.join(path.resolve(путьДовод), файл.имя) : файл.путьПоУмолчанию;
  console.log('--- ' + файл.имя + ' (' + путь + ') ---');

  if (!fs.existsSync(путь)) {
    шаг(false, файл.имя + ': файл не найден вовсе — ' + путь);
    console.log('');
    continue;
  }

  const текст = fs.readFileSync(путь, 'utf8');
  const текстБезКомментариев = убратьКомментарии(текст);
  найденныеМодули[файл.имя] = { путь, текст, текстБезКомментариев };

  const подключаетCrypto = /require\(\s*['"](?:node:)?crypto['"]\s*\)/.test(текстБезКомментариев);
  шаг(подключаетCrypto, файл.имя + ': файл подключает node:crypto (или crypto) хоть где-то');

  const естьRandomInt = /randomInt/.test(текстБезКомментариев);
  шаг(естьRandomInt, файл.имя + ': где-то в файле есть randomInt');

  for (const имяФункции of файл.функции) {
    const тело = извлечьТелоФункции(текстБезКомментариев, имяФункции);
    шаг(Boolean(тело), файл.имя + ': функция «' + имяФункции + '» нашлась в файле (иначе непонятно, что проверять)');
    if (тело) {
      шаг(!/Math\.random/.test(тело), файл.имя + ': в теле функции «' + имяФункции + '» нет Math.random');
    }
  }

  const нетMathRandomВоВсёмФайле = !/Math\.random/.test(текстБезКомментариев);
  шаг(нетMathRandomВоВсёмФайле, файл.имя + ': во всём коде файла без комментариев нигде нет Math.random');

  console.log('');
}

/* Поведенческую часть гоняем только на настоящих файлах проекта: копии
   для ломающего запуска лежат в отдельной папке без соседних require'ов
   (../../игры/деберц/деберц-правила.js и так далее) и корректно не подключились
   бы — это ожидаемо, не баг. */
if (!этоЛомающийЗапуск) {
  console.log('--- Поведение: деберц — 30 раздач, первая карта первого игрока ---');
  try {
    const деберц = require(найденныеМодули['деберц.js'].путь);
    const первыеКарты = new Set();
    for (let i = 0; i < 30; i++) {
      const п = деберц.раздать(null, { игроки: [1, 2] });
      const карта = п.игра.руки[0][0];
      первыеКарты.add(карта && карта.id);
    }
    шаг(первыеКарты.size >= 3, 'за 30 раздач первая карта первого игрока встретилась хотя бы в 3 разных видах (получилось: ' + первыеКарты.size + ' — ' + Array.from(первыеКарты).join(',') + ')');
  } catch (ошибка) {
    шаг(false, 'модуль деберца подключился и отработал 30 раздач без ошибки (поймано: ' + ошибка.message + ')');
  }
  console.log('');

  console.log('--- Поведение: морской бой — 200 раздач, кто ходит первым ---');
  try {
    const морбой = require(найденныеМодули['морской-бой.js'].путь);
    const значения = new Set();
    for (let i = 0; i < 200; i++) {
      const п = морбой.раздать(null, { игроки: [1, 2] });
      значения.add(п.игра.первый);
    }
    шаг(значения.has(0) && значения.has(1), 'за 200 раздач первым ходил и игрок 0, и игрок 1 (встретилось: ' + Array.from(значения).sort().join(',') + ')');
  } catch (ошибка) {
    шаг(false, 'модуль морского боя подключился и отработал 200 раздач без ошибки (поймано: ' + ошибка.message + ')');
  }
  console.log('');

  console.log('--- Поведение: шахматы — 200 раздач, жребий цвета ---');
  try {
    const шахматы = require(найденныеМодули['шахматы.js'].путь);
    const побывалиБелыми = new Set();
    for (let i = 0; i < 200; i++) {
      const п = шахматы.раздать(null, { игроки: ['a', 'b'] });
      for (const место of ['a', 'b']) {
        if (п.цвета[место] === 'белые') побывалиБелыми.add(место);
      }
    }
    шаг(побывалиБелыми.has('a') && побывалиБелыми.has('b'), 'за 200 раздач белыми побывало и место «a», и место «b» (побывали: ' + Array.from(побывалиБелыми).sort().join(',') + ')');
  } catch (ошибка) {
    шаг(false, 'модуль шахмат подключился и отработал 200 раздач без ошибки (поймано: ' + ошибка.message + ')');
  }
  console.log('');
} else {
  console.log('(поведение на ломающих копиях не проверяется — см. пояснение в шапке файла)');
  console.log('');
}

console.log('Итого проверок: ' + проверок + ', провалов: ' + ошибок);
process.exit(ошибок ? 1 : 0);
