'use strict';

/* =====================================================================
   ДОРОГА К ОФОРМЛЕНИЮ: рубашки и фоны должны быть достижимы.

   Владелец написал: «почему-то не вижу до сих пор в картах выбора
   рубашки и фона игры». Шесть рубашек и пять фонов были сделаны
   и опубликованы, но попасть к ним стало нельзя: единственная кнопка
   жила на экране настроек игры с ботом, а этот экран мы по его же
   просьбе убрали с пути — «Играть с ботом» начинает партию сразу.

   Та же беда, что была с нардами: сделано, а дороги нет. И не всплыла
   она ровно потому, что проверки ходили на экран оформления напрямую,
   а человек ходит с витрины.

   Поэтому здесь проверяется ДОРОГА, а не экран:
     витрина → «Дурак» → «Оформление» → рубашки на месте → «Назад».

   Отдельно проверяется, что из «Оформления» можно выйти пальцем.
   Замер показал беду, которую глазами не видно: содержимое экрана
   выше окна (812 точек против 640), а прокрутки нет ни у экрана,
   ни у страницы — кнопка «Назад» оказывалась недостижима, и человек
   застревал: стрелка Telegram на этой странице мёртвая, другого
   выхода нет.

   Запуск:
       node tests/дорога-к-оформлению.js
       node tests/дорога-к-оформлению.js 8080

   Число — порт локального сервера с игрой (по умолчанию 8080).
   Поднять его: node tests/локальный-сервер.js 8080
   ===================================================================== */

const path = require('path');
const робот = require(path.join(__dirname, 'браузер-робот.js'));

const ПОРТ = Number(process.argv[2] || 8080);
const АДРЕС = 'http://127.0.0.1:' + ПОРТ + '/index.html';

/* Окна нарочно низкие: на них беда и вылезает. 504 — самый тесный
   телефон, который мы держим; 640 — обычный. */
const ОКНА = [
  { ширина: 320, высота: 504 },
  { ширина: 320, высота: 640 }
];

let проверок = 0;
const провалы = [];

function проверить(условие, что) {
  проверок++;
  if (условие) {
    console.log('  ок   ' + что);
    return;
  }
  провалы.push(что);
  console.log('  ПРОВАЛ: ' + что);
}

function пауза(мс) {
  return new Promise(function (готово) { setTimeout(готово, мс); });
}

async function пройтиДорогу(браузер, окно) {
  const место = await браузер.newContext({ viewport: { width: окно.ширина, height: окно.высота } });
  const страница = await место.newPage();
  const ошибки = [];
  страница.on('pageerror', function (беда) { ошибки.push(беда.message); });

  await робот.безTelegram(страница);
  await страница.goto(АДРЕС);
  await пауза(700);

  console.log('\nОкно ' + окно.ширина + '×' + окно.высота + ':');

  // Дорогой человека: витрина → «Дурак».
  await страница.click('#кнопка-игра-дурак');
  await пауза(300);

  const есть = await страница.evaluate(function () {
    const кнопка = document.getElementById('кнопка-оформление-стол');
    return {
      экран: (document.querySelector('.экран--виден') || {}).id || '',
      кнопкаЕсть: Boolean(кнопка),
      виднаКнопка: Boolean(кнопка && кнопка.offsetParent)
    };
  });
  проверить(есть.экран === 'экран-меню', 'с витрины попали на экран игры');
  проверить(есть.кнопкаЕсть && есть.виднаКнопка,
    'кнопка «Оформление» видна там, куда человек и приходит');

  if (!есть.кнопкаЕсть) {
    await место.close();
    return ошибки;
  }

  await страница.click('#кнопка-оформление-стол');
  await пауза(500);

  const наЭкране = await страница.evaluate(function () {
    return {
      экран: (document.querySelector('.экран--виден') || {}).id || '',
      рубашек: document.querySelectorAll('#выбор-рубашки .оформление__выбор').length,
      картинок: document.querySelectorAll('#выбор-рубашки .оформление__выбор svg').length
    };
  });
  проверить(наЭкране.экран === 'экран-оформления', 'открылся экран «Оформление»');
  проверить(наЭкране.рубашек >= 6, 'все шесть рубашек на месте (нашлось ' + наЭкране.рубашек + ')');
  проверить(наЭкране.картинок >= 6, 'рубашки показаны рубашками, а не словами');

  /* Выход пальцем. Мотаем экран вниз ровно так, как это делает палец,
     и смотрим, попала ли кнопка «Назад» в видимую часть. */
  const выход = await страница.evaluate(function () {
    const экран = document.getElementById('экран-оформления');
    const назад = document.getElementById('кнопка-оформление-назад');
    if (!экран || !назад) return { есть: false };
    экран.scrollTop = экран.scrollHeight;
    const место = назад.getBoundingClientRect();
    return {
      есть: true,
      видна: место.bottom <= window.innerHeight + 1 && место.top >= 0,
      низ: Math.round(место.bottom),
      окно: window.innerHeight
    };
  });
  проверить(выход.есть && выход.видна,
    'до кнопки «Назад» можно домотать пальцем (низ ' + выход.низ + ' при окне ' + выход.окно + ')');

  await страница.evaluate(function () {
    document.getElementById('кнопка-оформление-назад').click();
  });
  await пауза(400);
  const вернулись = await страница.evaluate(function () {
    return (document.querySelector('.экран--виден') || {}).id || '';
  });
  проверить(вернулись === 'экран-меню', '«Назад» вернул туда, откуда пришли');

  await место.close();
  return ошибки;
}

(async function () {
  const браузер = await робот.chromium.launch();
  const всеОшибки = [];
  try {
    for (const окно of ОКНА) {
      const ошибки = await пройтиДорогу(браузер, окно);
      всеОшибки.push.apply(всеОшибки, ошибки);
    }
  } finally {
    await браузер.close();
  }

  проверить(всеОшибки.length === 0,
    'красных ошибок в консоли нет' + (всеОшибки.length ? ': ' + всеОшибки[0] : ''));

  console.log('\n----------------------------------------');
  console.log('Проверок сделано: ' + проверок);
  if (провалы.length === 0) {
    console.log('ИТОГ: до рубашек и фонов можно дойти и можно выйти обратно.');
    process.exit(0);
  }
  console.log('ПРОВАЛОВ: ' + провалы.length);
  for (const провал of провалы) console.log('  — ' + провал);
  process.exit(1);
})();
