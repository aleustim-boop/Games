'use strict';

/* =====================================================================
   ДОРОГА К ОФОРМЛЕНИЮ: рубашки и фоны должны быть достижимы.

   Владелец написал: «почему-то не вижу до сих пор в картах выбора
   рубашки и фона игры». Шесть рубашек и пять фонов были сделаны
   и опубликованы, но попасть к ним стало нельзя: единственная кнопка
   жила на экране настроек игры с ботом, а этот экран мы по его же
   просьбе убрали с пути — «Играть с ботом» начинает партию сразу.

   Та же беда, что была с нардами: сделано, а дороги нет. И не всплыла
   она ровно потому, что проверки ходили на экран оформления напрямую,
   а человек ходит с витрины.

   Поэтому здесь проверяется ДОРОГА, а не экран:
     витрина → «Дурак» → лобби → «⋯» → «Оформление» → сукно стола на месте
     → «Назад» (с 11 сентября — через лист «⋯» лобби, прежнего меню нет).

   11 сентября колода стала одной (рисунки владельца), выбор рубашки
   спрятан, а «Фон» стал «Сукном стола» на пять цветов. Проверка теперь
   ждёт именно этого: рубашек не видно, сукно — все цвета из двери.

   Отдельно проверяется, что из «Оформления» можно выйти пальцем.
   Замер показал беду, которую глазами не видно: содержимое экрана
   выше окна (812 точек против 640), а прокрутки нет ни у экрана,
   ни у страницы — кнопка «Назад» оказывалась недостижима, и человек
   застревал: стрелка Telegram на этой странице мёртвая, другого
   выхода нет.

   Запуск:
       node tests/дорога-к-оформлению.js
       node tests/дорога-к-оформлению.js 8080

   Число — порт локального сервера с игрой (по умолчанию 8080).
   Поднять его: node tests/локальный-сервер.js 8080
   ===================================================================== */

const path = require('path');
const робот = require(path.join(__dirname, 'браузер-робот.js'));
const { открытьЛист } = require(path.join(__dirname, 'сесть-за-стол.js'));

const ПОРТ = Number(process.argv[2] || 8080);
const АДРЕС = 'http://127.0.0.1:' + ПОРТ + '/index.html';

/* Окна нарочно низкие: на них беда и вылезает. 504 — самый тесный
   телефон, который мы держим; 640 — обычный. */
const ОКНА = [
  { ширина: 320, высота: 504 },
  { ширина: 320, высота: 640 }
];

let проверок = 0;
const провалы = [];

function проверить(условие, что) {
  проверок++;
  if (условие) {
    console.log('  ок   ' + что);
    return;
  }
  провалы.push(что);
  console.log('  ПРОВАЛ: ' + что);
}

function пауза(мс) {
  return new Promise(function (готово) { setTimeout(готово, мс); });
}

async function пройтиДорогу(браузер, окно) {
  const место = await браузер.newContext({ viewport: { width: окно.ширина, height: окно.высота } });
  const страница = await место.newPage();
  const ошибки = [];
  страница.on('pageerror', function (беда) { ошибки.push(беда.message); });

  await робот.безTelegram(страница);
  await страница.goto(АДРЕС);
  await пауза(700);

  console.log('\nОкно ' + окно.ширина + '×' + окно.высота + ':');

  /* Дорогой человека: витрина → «Дурак» → лобби → «⋯» → «Оформление».
     До 11 сентября «Оформление» было кнопкой прежнего меню дурака; меню
     заменили лобби, и строка «Оформление» живёт теперь в его листе «⋯». */
  await страница.click('#кнопка-игра-дурак');
  await пауза(300);
  const вЛобби = await страница.evaluate(function () {
    return (document.querySelector('.экран--виден') || {}).id || '';
  });
  проверить(вЛобби === 'экран-лобби', 'с витрины попали в лобби дурака (' + вЛобби + ')');

  let листОткрыт = '';
  try {
    листОткрыт = await открытьЛист(страница);
  } catch (беда) {
    листОткрыт = '';
  }
  const есть = await страница.evaluate(function () {
    const строка = document.getElementById('кнопка-лист-игры-оформление');
    return {
      строкаЕсть: Boolean(строка),
      виднаСтрока: Boolean(строка && строка.offsetParent && !строка.classList.contains('скрыт'))
    };
  });
  проверить(Boolean(листОткрыт), 'лист «⋯» лобби открылся (' + (листОткрыт || 'не открылся') + ')');
  проверить(есть.строкаЕсть && есть.виднаСтрока,
    'строка «Оформление» видна в листе — там, куда человек и приходит');

  if (!есть.виднаСтрока) {
    await место.close();
    return ошибки;
  }

  await страница.click('#кнопка-лист-игры-оформление');
  await пауза(500);

  /* С 11 сентября рубашка у колоды одна (картинка владельца), и выбор
     рубашки спрятан: показывать ряд из одной кнопки — звать выбирать то,
     чего нет. Главное на экране теперь «Сукно стола» — пять цветов.
     Сколько их должно быть, спрашиваем у самой двери сукна (ОбщийФон),
     а не держим число у себя; обещание владельцу — не меньше пяти. */
  const наЭкране = await страница.evaluate(function () {
    const раздел = document.getElementById('раздел-рубашки');
    const разделФона = document.getElementById('раздел-фона');
    const кнопкиСукна = Array.from(document.querySelectorAll('#выбор-фона .оформление__выбор'));
    return {
      экран: (document.querySelector('.экран--виден') || {}).id || '',
      рубашкиСпрятаны: !раздел || раздел.classList.contains('скрыт') || раздел.offsetParent === null,
      подписьСукна: разделФона ? ((разделФона.querySelector('.оформление__подпись') || {}).textContent || '').trim() : '',
      сукнаВидно: Boolean(разделФона && разделФона.offsetParent !== null),
      сукон: кнопкиСукна.length,
      сОбразцом: кнопкиСукна.filter(function (к) { return к.querySelector('[data-фон]'); }).length,
      вДвери: (window.ОбщийФон && typeof window.ОбщийФон.фоны === 'function') ? window.ОбщийФон.фоны().length : -1,
      названия: кнопкиСукна.map(function (к) { return ((к.querySelector('.оформление__имя') || {}).textContent || '').trim(); }).join(', ')
    };
  });
  проверить(наЭкране.экран === 'экран-оформления', 'открылся экран «Оформление»');
  проверить(наЭкране.рубашкиСпрятаны, 'выбора рубашки не видно — рубашка одна, выбирать нечего');
  проверить(наЭкране.сукнаВидно && наЭкране.подписьСукна === 'Сукно стола', 'раздел «Сукно стола» виден (подпись: «' + наЭкране.подписьСукна + '»)');
  проверить(наЭкране.вДвери >= 5 && наЭкране.сукон === наЭкране.вДвери,
    'все цвета сукна на месте: кнопок ' + наЭкране.сукон + ', у двери ' + наЭкране.вДвери + ' (' + наЭкране.названия + ')');
  проверить(наЭкране.сОбразцом === наЭкране.сукон && наЭкране.сукон > 0, 'сукно показано образцом цвета, а не одним словом');

  /* Выход пальцем. Раньше «Назад» стояла внизу, и проверка мотала экран
     до конца. 11 сентября оформитель перенёс её наверх — стрелкой «‹» над
     заголовком, — и «домотать до конца» стало уводить её за верхний край.
     Поэтому не гадаем, где она: сначала мотаем экран до конца (как палец,
     который ищет выход внизу), потом просим браузер довести кнопку в поле
     зрения ПРОКРУТКОЙ её экрана — ровно то, что может палец. Если кнопка
     лежит там, куда прокрутка не достаёт, она так и останется за краем. */
  const выход = await страница.evaluate(function () {
    const экран = document.getElementById('экран-оформления');
    const назад = document.getElementById('кнопка-оформление-назад');
    if (!экран || !назад) return { есть: false };
    экран.scrollTop = экран.scrollHeight;
    назад.scrollIntoView({ block: 'nearest', inline: 'nearest' });
    const место = назад.getBoundingClientRect();
    return {
      есть: true,
      видна: место.bottom <= window.innerHeight + 1 && место.top >= -1 && место.left >= -1 && место.right <= window.innerWidth + 1,
      верх: Math.round(место.top),
      низ: Math.round(место.bottom),
      ширина: Math.round(место.width),
      высота: Math.round(место.height),
      окно: window.innerHeight
    };
  });
  проверить(выход.есть && выход.видна,
    'до кнопки «Назад» можно добраться пальцем (кнопка ' + выход.верх + '..' + выход.низ + ' при окне ' + выход.окно + ')');
  проверить(выход.есть && выход.ширина >= 44 && выход.высота >= 44,
    'кнопка «Назад» не меньше 44×44 — под палец (' + выход.ширина + '×' + выход.высота + ')');

  await страница.evaluate(function () {
    document.getElementById('кнопка-оформление-назад').click();
  });
  await пауза(400);
  const вернулись = await страница.evaluate(function () {
    return (document.querySelector('.экран--виден') || {}).id || '';
  });
  проверить(вернулись === 'экран-лобби', '«Назад» вернул туда, откуда пришли — в лобби (' + вернулись + ')');

  await место.close();
  return ошибки;
}

(async function () {
  const браузер = await робот.chromium.launch();
  const всеОшибки = [];
  try {
    for (const окно of ОКНА) {
      const ошибки = await пройтиДорогу(браузер, окно);
      всеОшибки.push.apply(всеОшибки, ошибки);
    }
  } finally {
    await браузер.close();
  }

  проверить(всеОшибки.length === 0,
    'красных ошибок в консоли нет' + (всеОшибки.length ? ': ' + всеОшибки[0] : ''));

  console.log('\n----------------------------------------');
  console.log('Проверок сделано: ' + проверок);
  if (провалы.length === 0) {
    console.log('ИТОГ: до сукна стола можно дойти и можно выйти обратно.');
    process.exit(0);
  }
  console.log('ПРОВАЛОВ: ' + провалы.length);
  for (const провал of провалы) console.log('  — ' + провал);
  process.exit(1);
})();
