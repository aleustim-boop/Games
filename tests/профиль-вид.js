/* =====================================================================
   ПРОВЕРКА ВИДА ЭКРАНА «ПРОФИЛЬ» ПРИ СВЕТЛОЙ ТЕМЕ TELEGRAM.

   Зачем. 23.09 владелец прислал снимок из Telegram: экран «Профиль»
   был бледно-салатовым с зерном (сквозь него просвечивало сукно
   страницы, крашенное светлой темой), белый текст на нём не читался,
   у домино и морского боя стояли битые картинки, под очками — одинокий
   прочерк «—». Эта проверка ловит ровно эти беды:
     1) фон экрана тёмный: яркость (относительная, 0…1) меньше 0.2;
     2) ни одной битой картинки: у каждой <img> naturalWidth больше 0,
        у каждой строки игры есть значок — картинка или запасной кружок;
     3) подпись «место» читается: контраст с фоном не меньше 4.5;
     4) нет одинокого «—» под очками, когда сравнивать место не с чем.

   Где. index.html и шашки.html, ширины 390 и 768, поддельный Telegram
   со светлой темой; фон оформления по умолчанию и живой «туман» (при нём
   общая тёмная заливка экранов не действует — см. «ФОНЫ» ниже). Страницы берём со стенда http://localhost:8080/.
   Ответ сервера рейтинга подменяем своим — меряем код страницы, а не то,
   жив ли боевой сервер.

   Запуск:
       node tests/профиль-вид.js
   Ломающий запуск — подменить файл страницы испорченной КОПИЕЙ (файлы
   проекта не трогаем), путь к копии — доводом:
       node tests/профиль-вид.js --css <путь к копии style.css>
       node tests/профиль-вид.js --js <путь к копии js/профиль-экран.js>
   Копия со старым фоном (без своего background у экрана) обязана дать
   провал пункта 1.

   Снимки: tests/снимки/профиль-<страница>-<ширина>.png
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const { chromium, подготовитьПодделку, перехватить } = require('./браузер-робот.js');

const СТЕНД = 'http://localhost:8080/';
const ПАПКА_СНИМКОВ = path.join(__dirname, 'снимки');
if (!fs.existsSync(ПАПКА_СНИМКОВ)) fs.mkdirSync(ПАПКА_СНИМКОВ, { recursive: true });

/** Значение довода «--имя путь»; нет довода — null. */
function довод(имя) {
  const i = process.argv.indexOf(имя);
  if (i === -1) return null;
  const значение = process.argv[i + 1];
  if (!значение || !fs.existsSync(значение)) {
    console.error('довод ' + имя + ': файла «' + значение + '» нет — ломающий запуск без копии не имеет смысла');
    process.exit(2);
  }
  return значение;
}
const КОПИЯ_CSS = довод('--css');
const КОПИЯ_JS = довод('--js');

let всего = 0;
let провалов = 0;
function проверить(условие, слова) {
  всего++;
  if (условие) console.log('  ок    — ' + слова);
  else { провалов++; console.log('  ПЛОХО — ' + слова); }
}

