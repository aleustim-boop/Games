const ФОНЫ = [null, 'туман'];

async function дождатьсяЭкрана(страница, id) {
  try {
    await страница.waitForFunction(function (и) {
      const э = document.getElementById(и);
      return Boolean(э && э.classList.contains('экран--виден'));
    }, id, { timeout: 8000 });
    return true;
  } catch (сбой) { return false; }
}

/* Все замеры — внутри страницы: цвет считаем по вычисленным стилям. */
function замерить() {
  /** Цвет из вычисленного стиля → [r, g, b, a] в долях 0…1. */
  function разобрать(цвет) {
    let м = /^rgba?\(([^)]+)\)$/.exec(цвет);
    if (м) {
      const ч = м[1].split(/[\s,/]+/).filter(Boolean).map(parseFloat);
      return [ч[0] / 255, ч[1] / 255, ч[2] / 255, ч.length > 3 ? ч[3] : 1];
    }
    м = /^color\(srgb ([^)]+)\)$/.exec(цвет);
    if (м) {
      const ч = м[1].split(/[\s/]+/).filter(Boolean).map(parseFloat);
      return [ч[0], ч[1], ч[2], ч.length > 3 ? ч[3] : 1];
    }
    return null;
  }
  /** Относительная яркость по WCAG (0 — чёрный, 1 — белый). */
  function яркость(ц) {
    const лин = ц.slice(0, 3).map(function (к) {
      return к <= 0.03928 ? к / 12.92 : Math.pow((к + 0.055) / 1.055, 2.4);
    });
    return 0.2126 * лин[0] + 0.7152 * лин[1] + 0.0722 * лин[2];
  }
  /** Первый непрозрачный фон от узла вверх — то, что человек видит под ним. */
  function фонПод(узел) {
    for (let н = узел; н && н.nodeType === 1; н = н.parentElement) {
      const ц = разобрать(getComputedStyle(н).backgroundColor);
      if (ц && ц[3] > 0.5) return { цвет: ц, узел: н.id || н.tagName };
    }
    return null;
  }

  const р = {};
  const эк = document.getElementById('экран-профиля-игрока');
  р.экранЕсть = Boolean(эк);
  if (!эк) return р;

  const фон = фонПод(эк);
  р.фонНайден = Boolean(фон);
  if (фон) {
    р.фонУзел = фон.узел;
    р.яркостьФона = яркость(фон.цвет);
  }

  const место = эк.querySelector('.профиль-карточка__место');
  р.местоЕсть = Boolean(место);
  if (место && фон) {
    р.текстМеста = место.textContent.trim();
    const цТекста = разобрать(getComputedStyle(место).color);
    const а = яркость(цТекста);
    const б = яркость(фон.цвет);
    р.контрастМеста = (Math.max(а, б) + 0.05) / (Math.min(а, б) + 0.05);
  }

  const картинки = Array.prototype.slice.call(эк.querySelectorAll('img'));
  р.картинок = картинки.length;
  р.битые = картинки.filter(function (к) { return !(к.naturalWidth > 0); })
    .map(function (к) { return к.getAttribute('src'); });

  const строки = Array.prototype.slice.call(эк.querySelectorAll('.профиль-очки__строка'));
  р.строк = строки.length;
  р.строкБезЗначка = строки.filter(function (с) {
    const з = с.querySelector('.профиль-очки__значок');
    if (!з) return true;
    return з.tagName === 'IMG' ? !(з.naturalWidth > 0) : !з.classList.contains('профиль-очки__значок--запаска');
  }).map(function (с) { return с.getAttribute('data-игра'); });
  р.запасок = эк.querySelectorAll('.профиль-очки__значок--запаска').length;

  const карточка = document.getElementById('профиль-карточка');
  р.одинокийПрочерк = Boolean(карточка) && Array.prototype.some.call(
    карточка.querySelectorAll('span'), function (с) { return с.textContent.trim() === '—'; });
  return р;
}

async function прогон(браузер, стр, размер, фонОформления) {
  const метка = стр.файл + ' ' + размер.ш + ' фон «' + (фонОформления || 'по умолчанию') + '»';
  const контекст = await браузер.newContext({
    viewport: { width: размер.ш, height: размер.в }, hasTouch: true, colorScheme: 'light'
  });
  const страница = await контекст.newPage();
  const ошибки = [];
  страница.on('pageerror', function (о) { ошибки.push(о.message); });

  await подготовитьПодделку(страница, { версия: '8.0', тема: СВЕТЛАЯ_ТЕМА });
  /* Один перехват на всё: дверь рейтинга — свой ответ; style.css и
     js/профиль-экран.js — испорченная копия, если её дали доводом. */
  const примета = new RegExp('(/рейтинг(?:\\?|$))|(/style\\.css(?:\\?|$))|(/js/профиль-экран\\.js(?:\\?|$))');
  await перехватить(страница, примета, function (путь, запрос, адрес) {
    if (/\/style\.css(\?|$)/.test(адрес)) {
      if (КОПИЯ_CSS) путь.fulfill({ status: 200, contentType: 'text/css; charset=utf-8', body: fs.readFileSync(КОПИЯ_CSS) });
      else путь.continue();
      return;
    }
    if (/\/js\/профиль-экран\.js(\?|$)/.test(адрес)) {
      if (КОПИЯ_JS) путь.fulfill({ status: 200, contentType: 'text/javascript; charset=utf-8', body: fs.readFileSync(КОПИЯ_JS) });
      else путь.continue();
      return;
    }
    путь.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(ОТВЕТ_РЕЙТИНГА) });
  });

  await страница.goto(СТЕНД + encodeURI(стр.файл), { waitUntil: 'load' });
  проверить(await дождатьсяЭкрана(страница, стр.стартовыйЭкран), метка + ': стартовый экран «' + стр.стартовыйЭкран + '» открылся');
  if (фонОформления) {
    /* Ставим признак прямо на страницу, как его ставит сама игра при
       выборе в «Оформлении», и сверяем, что он встал. */
    const встал = await страница.evaluate(function (ф) {
      document.documentElement.setAttribute('data-фон', ф);
      return document.documentElement.getAttribute('data-фон') === ф;
    }, фонОформления);
    проверить(встал, метка + ': выбран фон оформления «' + фонОформления + '»');
  }
  await страница.click(стр.вкладка);
  const открыт = await дождатьсяЭкрана(страница, 'экран-профиля-игрока');
  проверить(открыт, метка + ': вкладка «Профиль» открыла экран профиля');

  /* Ждём, пока строки очков дорисуются и все картинки загрузятся или
     упадут (битая заменяется запасным значком сразу по ошибке). */
  try {
    await страница.waitForFunction(function () {
      const эк = document.getElementById('экран-профиля-игрока');
      if (!эк || !эк.querySelector('.профиль-очки__строка')) return false;
      return Array.prototype.every.call(эк.querySelectorAll('img'), function (к) { return к.complete; });
    }, null, { timeout: 8000 });
  } catch (сбой) { /* ниже покраснеет пункт про строки */ }
  await страница.waitForTimeout(300);

  const з = await страница.evaluate(замерить);
  проверить(з.экранЕсть, метка + ': узел #экран-профиля-игрока найден');
  проверить(з.фонНайден, метка + ': под экраном нашёлся непрозрачный фон');
  проверить(з.фонНайден && з.яркостьФона < 0.2,
    метка + ': п.1 фон тёмный — яркость ' + (з.яркостьФона === undefined ? '?' : з.яркостьФона.toFixed(3)) +
    ' (< 0.2), фон даёт узел «' + з.фонУзел + '»');
  проверить(з.строк > 0, метка + ': п.2 строки очков по играм есть (' + з.строк + ')');
  проверить(з.картинок > 0, метка + ': п.2 хоть одна настоящая картинка-значок на экране есть (' + з.картинок + ')');
  проверить(з.битые && з.битые.length === 0,
    метка + ': п.2 битых картинок нет' + (з.битые && з.битые.length ? ' — битые: ' + з.битые.join(', ') : ''));
  проверить(з.строкБезЗначка && з.строкБезЗначка.length === 0,
    метка + ': п.2 у каждой строки значок — картинка или запасной кружок (запасных ' + з.запасок + ')' +
    (з.строкБезЗначка && з.строкБезЗначка.length ? ' — без значка: ' + з.строкБезЗначка.join(', ') : ''));
  проверить(з.местоЕсть && з.контрастМеста >= 4.5,
    метка + ': п.3 подпись «' + з.текстМеста + '» читается — контраст ' +
    (з.контрастМеста ? з.контрастМеста.toFixed(2) : '?') + ' (≥ 4.5)');
  проверить(!з.одинокийПрочерк, метка + ': п.4 в карточке нет одинокого «—»');
  проверить(ошибки.length === 0, метка + ': исключений на странице нет' + (ошибки.length ? ' — ' + ошибки.join(' | ') : ''));

  if (!КОПИЯ_CSS && !КОПИЯ_JS) {
    const снимок = path.join(ПАПКА_СНИМКОВ, 'профиль-' + стр.имя + '-' + размер.ш +
      (фонОформления ? '-' + фонОформления : '') + '.png');
    await страница.screenshot({ path: снимок });
    console.log('  снимок: ' + снимок);
  }
  await контекст.close();
}

(async function () {
  if (КОПИЯ_CSS) console.log('ЛОМАЮЩИЙ ЗАПУСК: style.css подменён копией ' + КОПИЯ_CSS);
  if (КОПИЯ_JS) console.log('ЛОМАЮЩИЙ ЗАПУСК: js/профиль-экран.js подменён копией ' + КОПИЯ_JS);
  const браузер = await chromium.launch();
  for (const стр of СТРАНИЦЫ) {
    for (const размер of ШИРИНЫ) {
      for (const фон of ФОНЫ) {
        console.log('\n=== ' + стр.файл + ' ' + размер.ш + 'x' + размер.в + ', светлая тема Telegram, фон «' +
          (фон || 'по умолчанию') + '» ===');
        await прогон(браузер, стр, размер, фон);
      }
    }
  }
  await браузер.close();
  console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
  process.exit(провалов > 0 ? 1 : 0);
})().catch(function (е) {
  console.error('ПРОВАЛ ЗАПУСКА: ' + (е && е.stack || е));
  process.exit(2);
});
