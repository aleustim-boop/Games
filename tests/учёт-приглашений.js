function случайПерезапуск() {
  console.log('\n(з) Перезапуск: новый процесс на той же папке данных');
  приглашения.дописать();
  const доводы = [__filename, '--перезапуск', '--корень=' + КОРЕНЬ_СЕРВЕРА];
  const итог = spawnSync(process.execPath, доводы, { env: process.env, encoding: 'utf8', timeout: 60000 });
  проверить('(з) второй процесс отработал', итог.status === 0, (итог.stderr || '') + (итог.error || ''));
  let сДиска = null;
  try {
    сДиска = JSON.parse(fs.readFileSync(path.join(ПАПКА_ДАННЫХ, 'приглашения.json'), 'utf8')).записи;
  } catch (сбой) {
    сДиска = null;
  }
  проверить('(з) файл учёта лежит во временной папке и читается', Boolean(сДиска));
  if (!сДиска) return;
  const открытая = сДиска[номерНезакрытого];
  const закрытая = сДиска[номерПолнойЦепочки];
  const что = function (з) { return з ? з.события.map(function (с) { return с.что; }) : []; };
  проверить('(з) незакрытая запись получила «комнатаПотеряна» последним событием',
    открытая && что(открытая)[что(открытая).length - 1] === 'комнатаПотеряна', JSON.stringify(что(открытая)));
  проверить('(з) доигранная запись не тронута (нет «комнатаПотеряна»)',
    закрытая && что(закрытая).indexOf('комнатаПотеряна') === -1, JSON.stringify(что(закрытая)));
  const сколькоНезакрытых = Object.keys(сДиска).filter(function (н) {
    const с = что(сДиска[н]);
    return с.indexOf('итог') === -1 && с.indexOf('комнатаПотеряна') === -1;
  }).length;
  проверить('(з) после перезапуска незакрытых записей не осталось', сколькоНезакрытых === 0,
    'незакрытых: ' + сколькоНезакрытых);
}

