'use strict';
const assert = require('node:assert/strict');
const П = require('../js/деберц-правила.js'), Б = require('../js/деберц-бот.js'), М = require('../js/деберц-память.js');
let текст = null;
const носитель = { getItem: () => текст, setItem: (_, v) => { текст = v; } };
let память = М.открыть(носитель);
память.настроить('звук', false);
память.настроить('уровень', 'сложный');
assert.deepEqual(М.открыть(носитель).настройки(), { звук: false, уровень: 'сложный', цель: 301, режим: '2' });
const фазы = new Set();
for (const уровень of М.уровни) {
  const цель = П.цели[М.уровни.indexOf(уровень)];
  память.новая(уровень, цель);
  let шаг = 0;
  while (память.игра.фаза !== 'конец') {
    assert(++шаг < 5000);
    const и = память.игра; фазы.add(и.фаза);
    if (и.фаза === 'торговля') память.ход('торг', и.ход, Б.козырь(и.руки[и.ход], П.вариантыКозыря(и), уровень) ?? (П.обязанВыбрать(и) ? П.вариантыКозыря(и)[0] : null));
    else if (и.фаза === 'игра') память.ход('карта', и.ход, Б.карта(П.доступные(и, и.ход), и.стол[0]?.карта, и.козырь, уровень, и.сыграно).id);
    else if (и.фаза === 'взятка') память.ход('взятка');
    else память.ход('раздача');
    const восстановлена = М.открыть(носитель);
    assert.equal(восстановлена.ошибка, '');
    assert.deepEqual(восстановлена.игра, память.игра, 'Любой ход переживает перезапуск');
    if (память.игра.историяРаздач.length) {
      const история = память.игра.историяРаздач;
      assert.equal(new Set(история.map(р => р.номер)).size, история.length, 'Раздачи не дублируются');
      assert.deepEqual(история.reduce((с, р) => с.map((n, i) => n + р.запись[i]), память.игра.счёт.map(() => 0)), память.игра.счёт, 'История сходится с общим счётом');
    }
    assert.equal(восстановлена.уровень, уровень);
    assert.equal(восстановлена.игра.цель, цель);
    память = восстановлена;
  }
  assert.equal(память.результаты()[0].цель, цель);
}
assert.equal(память.результаты().length, 3);
for (let i = 0; i < 10; i++) память = М.открыть(носитель);
assert.equal(память.результаты().length, 3, 'Итог не дублируется');
assert(фазы.has('торговля') && фазы.has('игра') && фазы.has('взятка') && фазы.has('итог'));
память.новая();
const сохранено = текст;
assert.throws(() => память.ход('карта', 0, '♠Т'));
assert.equal(текст, сохранено, 'Незаконное действие не записывается');
память.ход('сдача');
assert.equal(память.результаты()[0].сдался, true);
assert.equal(М.открыть(носитель).игра.победитель, 1);
const повреждённая = JSON.parse(текст);
повреждённая.партия.ходы = [['карта', 0, '♠Т']];
текст = JSON.stringify(повреждённая);
const восстановление = М.открыть(носитель);
assert.equal(восстановление.игра, null);
assert.equal(восстановление.результаты().length, 4, 'История цела при испорченной партии');
assert(восстановление.ошибка);
const безПамяти = М.открыть({ getItem() { throw Error(); }, setItem() { throw Error(); } });
безПамяти.новая(); безПамяти.ход('сдача');
assert.equal(безПамяти.игра.фаза, 'конец'); assert(безПамяти.ошибка);
const к = (имя, масть = '♠') => ({ имя, масть, id: масть + имя });
const варианты = [к('7'), к('Т', '♥')];
assert.equal(Б.карта(варианты, null, '♦', 'лёгкий', [], () => 0).id, '♠7');
assert.equal(Б.карта(варианты, null, '♦', 'обычный').id, '♠7');
assert.equal(Б.карта(варианты, null, '♦', 'сложный').id, '♥Т');
assert.equal(Б.карта([к('7'), к('10', '♥')], null, '♦', 'сложный', [к('Т', '♥')]).id, '♥10');
console.log('Деберц: три уровня, восстановление каждого хода, результаты без дублей, сдача, повреждение и запрет памяти — OK');
