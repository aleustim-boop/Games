/** Читаем файл с любыми переводами строк как с «\n» — иначе порча из
    нескольких строк не нашла бы своего места в файле с «\r\n». */
function сЛюбымПереводом(ломка) {
  return function (текст) {
    const ровный = текст.replace(/\r\n/g, '\n');
    const испорчено = ломка(ровный);
    return испорчено === ровный ? текст : испорчено;
  };
}

async function ломающиеЗапуски() {
  console.log('\n=== Ломающие запуски: бот испорчен на копии, проверка обязана покраснеть ===');
  for (const л of ЛОМКИ) {
    серверМолчит = Boolean(л.молчит);
    const с = await спросить(нажатие(801, 'не-возврат'), сЛюбымПереводом(л.ломка));
    серверМолчит = false;
    const м = удачныйОтказ(с, 801);
    const покраснело = л.покраснело ? л.покраснело(с)
      : л.мерки.every(function (мерка) { return м[мерка] === false; });
    проверок++;
    if (покраснело) {
      console.log('  ок   — поломка поймана: ' + л.имя);
    } else {
      провалов++;
      console.log('  СБОЙ — поломку проверка не ловит: ' + л.имя);
    }
  }
}

async function главная() {
  const толькоЛомающий = process.argv.indexOf('--сломать') !== -1;

  try {
    if (!толькоЛомающий) await основныеСценарии();
    await ломающиеЗапуски();
  } finally {
    for (const папка of временныеПапки) {
      try { fs.rmSync(папка, { recursive: true, force: true }); } catch (ошибка) { /* временная папка не критична */ }
    }
  }

  console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);
  process.exit(провалов === 0 ? 0 : 1);
}

главная().catch(function (ошибка) {
  console.error('Проверка упала с технической ошибкой: ' + ошибка.stack);
  process.exit(1);
});
