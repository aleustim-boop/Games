// Поддельные Telegram и сервер комнат: подменяем https.request на весь процесс
// ---------------------------------------------------------------------------

const ОТПРАВЛЕНО = [];         // {метод, тело} — что бот сказал Telegram
const СЕРВЕРУ = [];            // {путь, тело} — что бот сказал серверу комнат
let серверМолчит = false;      // true — сервер комнат обрывает связь
let серверОтказывает = false;  // true — сервер комнат отвечает 403 и { ок: false }
let очередьОбновлений = [];
let счётЗапросовGetUpdates = 0;

https.request = function (опции, колбэк) {
  const запрос = new EventEmitter();
  запрос.end = function (телоBuf) {
    let тело = {};
    try { тело = телоBuf ? JSON.parse(телоBuf.toString('utf8')) : {}; } catch (ошибка) { /* не важно */ }
    const путь = String((опции && опции.path) || '');

    function ответить(данные, задержкаМс, номер) {
      setTimeout(function () {
        const ответ = new EventEmitter();
        ответ.setEncoding = function () {};
        ответ.statusCode = номер || 200;
        колбэк(ответ);
        ответ.emit('data', JSON.stringify(данные));
        ответ.emit('end');
      }, задержкаМс || 0);
    }

    // Не Telegram — значит, сервер комнат
    if (String(опции && опции.hostname) !== 'api.telegram.org') {
      let читаемыйПуть = путь;
      try { читаемыйПуть = decodeURIComponent(путь); } catch (ошибка) { /* оставим как есть */ }
      СЕРВЕРУ.push({ путь: читаемыйПуть, тело: тело });
      if (серверМолчит) {
        setTimeout(function () { запрос.emit('error', new Error('сервер комнат выключен')); }, 0);
        return;
      }
      if (серверОтказывает) { ответить({ ок: false, ошибка: 'Эта дверь только для бота игры' }, 0, 403); return; }
      ответить({ ок: true });
      return;
    }

    const метод = путь.slice(путь.lastIndexOf('/') + 1);
    if (метод === 'getUpdates') {
      счётЗапросовGetUpdates++;
      if (очередьОбновлений.length) {
        const пачка = очередьОбновлений;
        очередьОбновлений = [];
        ответить({ ok: true, result: пачка }, 0);
      } else {
        /* Пустой ответ — через десять минут: старые боты прошлых сценариев
           не умирают, и быстрый пустой ответ дал бы им перехватить апдейт
           следующего сценария (см. tests/бот-приглашение-в-игру.js). */
        ответить({ ok: true, result: [] }, 10 * 60 * 1000);
      }
      return;
    }

    ОТПРАВЛЕНО.push({ метод: метод, тело: тело });
    if (метод === 'getMe') { ответить({ ok: true, result: { username: 'ТестБот' } }); return; }
    if (метод === 'setChatMenuButton') { ответить({ ok: true, result: true }); return; }
    ответить({ ok: true, result: { message_id: 1 } });
  };
  запрос.on = EventEmitter.prototype.on.bind(запрос);
  запрос.destroy = function () {};
  return запрос;
};

