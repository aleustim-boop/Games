/* =====================================================================
   Проверка: бот понимает кнопку «Не присылать» в письме «давно не
   заходили» (callback_data 'не-возврат', штаб/план-возврат-ушедших.md, Э4):
   говорит серверу комнат (POST /не-возврат), отвечает человеку окном
   и убирает нажатую кнопку, оставляя «Играть».

   Стенд тот же, что у tests/бот-позвать-друга.js: копия bot/*.js
   и server/названия.js во временной папке, ПОДДЕЛЬНЫЙ .env с выдуманным
   токеном, https.request подменён на весь процесс — подделаны и Telegram,
   и сервер комнат (различаем по имени хоста). Настоящий bot/.env
   не читаем, в сеть не ходим.

   Запуск:            node tests/бот-не-возврат.js
   Только поломки:    node tests/бот-не-возврат.js --сломать
   ===================================================================== */

