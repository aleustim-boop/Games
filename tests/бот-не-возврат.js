/** Собираем стенд. ломка — функция (текст файла бот.js) → испорченный текст;
    если она ничего не изменила — это беда самой проверки: ломать нечего,
    значит, она смотрит не туда. */
function собратьСтенд(ломка) {
  const рут = fs.mkdtempSync(path.join(os.tmpdir(), 'не-возврат-'));
  временныеПапки.push(рут);
  const папкаБота = path.join(рут, 'bot');
  const папкаСервера = path.join(рут, 'server');
  fs.mkdirSync(папкаБота);
  fs.mkdirSync(папкаСервера);

  for (const имя of fs.readdirSync(path.join(КОРЕНЬ, 'bot'))) {
    if (!имя.endsWith('.js') || имя.indexOf('проверка-') === 0) continue;
    let текст = fs.readFileSync(path.join(КОРЕНЬ, 'bot', имя), 'utf8');
    if (ломка && имя === 'бот.js') {
      const испорчено = ломка(текст);
      if (испорчено === текст) {
        throw new Error('ломающий запуск: порча не нашла своего места в bot/бот.js — ' +
          'проверку чинить раньше, чем верить её зелёному цвету');
      }
      текст = испорчено;
    }
    fs.writeFileSync(path.join(папкаБота, имя), текст, 'utf8');
  }

  fs.copyFileSync(ИСХОДНЫЕ_НАЗВАНИЯ, path.join(папкаСервера, 'названия.js'));
  fs.writeFileSync(path.join(папкаБота, '.env'),
    'BOT_TOKEN=' + ТОКЕН + '\nGAME_URL=' + GAME_URL + '\n', 'utf8');

  return path.join(папкаБота, 'бот.js');
}

/** Письмо «давно не заходили», как его шлёт сервер: в одной строке
    «Играть» и «Не присылать». безИграть — письмо только с кнопкой отказа. */
function письмо(номерЧата, безИграть) {
  const отказ = { text: 'Не присылать', callback_data: 'не-возврат' };
  const играть = { text: 'Играть', web_app: { url: 'https://game.example/index.html' } };
  return {
    message_id: 77,
    chat: { id: номерЧата, type: 'private' },
    text: 'Давно не заходили — заглянете?',
    reply_markup: { inline_keyboard: [безИграть ? [отказ] : [играть, отказ]] }
  };
}

/** Нажатие кнопки в формате апдейта Telegram. */
function нажатие(номер, слово, безИграть) {
  return {
    update_id: Math.floor(Math.random() * 1e9),
    callback_query: {
      id: 'нажатие-' + номер,
      from: { id: номер, first_name: 'Игрок', is_bot: false },
      message: письмо(номер, безИграть),
      data: слово
    }
  };
}

/** Запускаем бота на свежем стенде с одним апдейтом и ждём, пока он
    обработает его целиком (второй, уже пустой, getUpdates — бот уснул).
    Возвращаем { телеграму — всё, что бот сказал Telegram, серверу —
    запросы к серверу комнат }. */
async function спросить(апдейт, ломка) {
  const путьКБоту = собратьСтенд(ломка);
  очередьОбновлений = [апдейт];
  const началоОтправок = ОТПРАВЛЕНО.length;
  const началоСерверу = СЕРВЕРУ.length;
  const счётДоЗапроса = счётЗапросовGetUpdates;

  require(путьКБоту);   // запускает работать() тут же, внутри процесса проверки

  for (let раз = 0; раз < 300 && счётЗапросовGetUpdates < счётДоЗапроса + 2; раз++) {
    await пауза(10);
  }
  return { телеграму: ОТПРАВЛЕНО.slice(началоОтправок), серверу: СЕРВЕРУ.slice(началоСерверу) };
}

/** Тело первого вызова данного метода Telegram в этом сценарии (или null). */
function вызов(итог, метод) {
  const нашлись = итог.телеграму.filter(function (з) { return з.метод === метод; });
  return нашлись.length ? нашлись[0].тело : null;
}

const ГОТОВО = 'Готово: напоминаний «давно не заходили» больше не будет. ' +
  'Итоги партий и приглашения друзей приходят как раньше.';
const НЕ_ВЫШЛО = 'Сейчас не получилось — нажмите ещё раз попозже.';

/** Всё ли в порядке при удачном отказе — одна мерка и для сценариев, и для ломок. */
function удачныйОтказ(с, номер) {
  const окно = вызов(с, 'answerCallbackQuery') || {};
  const правка = вызов(с, 'editMessageReplyMarkup');
  const строки = (правка && правка.reply_markup && правка.reply_markup.inline_keyboard) || null;
  return {
    одинЗапрос: с.серверу.length === 1,
    дверь: !!с.серверу[0] && с.серверу[0].путь === '/не-возврат',
    кого: !!с.серверу[0] && с.серверу[0].тело.кого === номер,
    пропуск: !!с.серверу[0] && с.серверу[0].тело.пропускБота === ПРОПУСК,
    окно: окно.text === ГОТОВО && окно.show_alert === true && окно.callback_query_id === 'нажатие-' + номер,
    кнопки: !!строки && строки.length === 1 && строки[0].length === 1 && строки[0][0].text === 'Играть' &&
      правка.chat_id === номер && правка.message_id === 77
  };
}

