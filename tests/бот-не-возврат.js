const https = require('https');
const crypto = require('crypto');
const { EventEmitter } = require('events');

const КОРЕНЬ = path.join(__dirname, '..');
const ИСХОДНЫЕ_НАЗВАНИЯ = path.join(КОРЕНЬ, 'server', 'названия.js');

let проверок = 0;
let провалов = 0;
const временныеПапки = [];

function проверить(описание, условие, подробности) {
  проверок++;
  if (условие) { console.log('  ок   — ' + описание); return; }
  провалов++;
  console.log('  СБОЙ — ' + описание + (подробности ? '\n         ' + подробности : ''));
}

function пауза(мс) { return new Promise(function (готово) { setTimeout(готово, мс); }); }

/* Выдуманный токен собран из кусочков — GitHub узнаёт токены Telegram
   по виду строки и присылает ложную тревогу об утечке, если написать
   его одной строкой (см. объяснение в tests/проверка-бота-лаунчера.js). */
function выдуманныйТокен() {
  const номерБота = [1, 2, 3, 4, 5, 6, 7, 8, 9, 0].join('');
  return номерБота + ':' + 'тест'.repeat(9);
}
const ТОКЕН = выдуманныйТокен();
// Пропуск бот и сервер считают каждый у себя — здесь считаем третий раз, для сверки
const ПРОПУСК = crypto.createHash('sha256').update('стол-из-чата:' + ТОКЕН, 'utf8').digest('hex');

// Адрес сервера комнат зашит в хвостик GAME_URL «?сервер=».
const АДРЕС_СЕРВЕРА_КОМНАТ = 'https://rooms.example:8790';
const GAME_URL = 'https://game.example/sbornik?сервер=' + encodeURIComponent(АДРЕС_СЕРВЕРА_КОМНАТ);

