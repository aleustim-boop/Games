'use strict';

/* =====================================================================
   КАК ЗАСЧИТЫВАЕТСЯ ИТОГ ПАРТИИ — проверка счёта побед, а не правил.

   ЗАЧЕМ ЭТОТ ФАЙЛ. В браузере обнаружилось вот что: партию вчетвером
   человек выигрывает, на экране крупно написано «Вы выиграли!», а в рамке
   под заголовком стоит «Ничья серию не прерывает. Побед подряд: 0».
   Победа не пошла ни в серию, ни в рекорды, и звук победы не прозвучал.
   В игре парами то же самое наоборот: «Ваша пара проиграла», а серия побед
   уцелела, как будто была ничья.

   ОТЧЕГО ТАК. Партия записывает итог именем того, кто остался дураком:
   вдвоём это «бот» либо «человек», а компанией — «бот-3», «бот-4»
   или даже «человек и бот-3» (в парах дурак не один, а пара). Счёт же
   побед разбирает ровно два слова — «бот» (я выиграл) и «человек»
   (я проиграл). Всё остальное для него «ничья».

   ЧТО СЧИТАЕТ ЭТОТ ФАЙЛ. Играет партии ботами до конца и по каждой
   спрашивает два вопроса:
     1) кто на самом деле остался дураком — есть ли среди них человек;
     2) как этот итог засчитает игра (развилка повторена здесь словами,
        см. «какЗасчитает» — она списана с «подвестиСерию» в js/game.js).
   Расхождение — это и есть незасчитанная победа или неучтённое поражение.

   Правил игры файл не проверяет: для этого есть автопрогон-правил-компанией.

   Запуск:  node tests/как-считается-итог-компанией.js
   ===================================================================== */

const путьКИгре = require('path').join(__dirname, '..', 'js', 'game.js');
const правила = require(путьКИгре);

const ПАРТИЙ_НА_СОСТАВ = 200;
const ПОТОЛОК_ХОДОВ = 900;

/**
 * Как итог засчитает сама игра. Это не наша выдумка, а списанная развилка
 * из «подвестиСерию» и «засчитатьИтог» (js/game.js): там смотрят на строку
 * «результат» и знают ровно два слова.
 */
function какЗасчитает(результат) {
  if (результат === 'бот') return 'победа';
  if (результат === 'человек') return 'поражение';
  return 'ничья';
}

/** Как надо по-честному: смотрим, кто вправду остался с картами. */
function какНаСамомДеле(партия) {
  const проигравшие = партия.проигравшие || [];
  if (проигравшие.length === 0) return 'ничья';
  return проигравшие.indexOf('человек') !== -1 ? 'поражение' : 'победа';
}

/**
 * Слепок стола: по нему видно, сдвинулась ли партия хоть на шаг.
 * Считать надо ВСЁ, что меняется от хода, — иначе отбитая карта (стол той же
 * длины, фаза та же) выглядит как «ничего не произошло», и проверка запишет
 * зависание там, где партия шла отлично. На этом мы один раз уже обожглись.
 */
function слепок(партия) {
  const вРуках = партия.игроки.map((и) => (партия.руки[и] || []).length).join('/');
  const отбитых = партия.стол.filter((пара) => пара.защита).length;
  return [правила.фаза(партия), партия.стол.length, отбитых, партия.отбой.length,
          партия.колода.length, вРуках, партия.атакует, (партия.пасы || []).join(',')].join('|');
}

/** Одна партия ботами до конца. Вернёт саму партию или null, если зависла. */
function сыгратьПартию(настройки) {
  const партия = правила.создатьПартию(настройки);
  for (let ход = 0; ход < ПОТОЛОК_ХОДОВ && !партия.завершена; ход++) {
    const чей = правила.ктоХодит(партия);
    if (!чей) break;
    const было = слепок(партия);
    правила.ходБота(партия, чей);
    if (слепок(партия) === было) return null;   // ход ничего не изменил — застряли
  }
  return партия.завершена ? партия : null;
}

function проверитьСостав(название, настройки) {
  const счёт = { победа: 0, поражение: 0, ничья: 0 };
  const незасчитано = { победа: 0, поражение: 0 };
  const примеры = [];
  let зависших = 0;

  for (let i = 0; i < ПАРТИЙ_НА_СОСТАВ; i++) {
    const партия = сыгратьПартию(Object.assign({ сложность: 'обычный' }, настройки));
    if (!партия) { зависших++; continue; }
    const честно = какНаСамомДеле(партия);
    const посчитано = какЗасчитает(партия.результат);
    счёт[честно]++;
    if (честно !== посчитано) {
      if (честно === 'победа') незасчитано.победа++;
      if (честно === 'поражение') незасчитано.поражение++;
      if (примеры.length < 3) {
        примеры.push('дурак(и): ' + (партия.проигравшие || []).join(' и ') +
                     ' → в «результате» записано «' + партия.результат +
                     '», игра засчитает это как «' + посчитано + '», а на деле это ' + честно);
      }
    }
  }

  console.log('--- ' + название + ' ---');
  console.log('  партий: ' + ПАРТИЙ_НА_СОСТАВ + ', из них зависших: ' + зависших);
  console.log('  по-честному: побед ' + счёт.победа + ', поражений ' + счёт.поражение +
              ', ничьих ' + счёт.ничья);
  const плохо = незасчитано.победа + незасчитано.поражение;
  if (плохо === 0) {
    console.log('  всё засчитано верно');
  } else {
    console.log('  НЕ ЗАСЧИТАНО: побед ' + незасчитано.победа +
                ', поражений ' + незасчитано.поражение +
                ' (это ' + Math.round(плохо * 100 / ПАРТИЙ_НА_СОСТАВ) + '% партий)');
    примеры.forEach((п) => console.log('    ' + п));
  }
  console.log('');
  return плохо;
}

console.log('Проверяем не правила, а счёт побед: попадает ли итог партии в серию и рекорды.\n');

let всегоПлохо = 0;
всегоПлохо += проверитьСостав('вдвоём с ботом (как было всегда)', { игроков: 2 });
всегоПлохо += проверитьСостав('втроём', { игроков: 3 });
всегоПлохо += проверитьСостав('вчетвером', { игроков: 4 });
всегоПлохо += проверитьСостав('вчетвером, переводной', { игроков: 4, переводной: true });
всегоПлохо += проверитьСостав('вчетвером, парами', { игроков: 4, парами: true });
всегоПлохо += проверитьСостав('впятером', { игроков: 5 });
всегоПлохо += проверитьСостав('вшестером', { игроков: 6 });

if (всегоПлохо === 0) {
  console.log('=== Итог: все победы и поражения засчитываются правильно ===');
} else {
  console.log('=== Итог: ' + всегоПлохо + ' партий засчитаны неверно. ' +
              'Человек увидит на экране один итог, а в счёте побед — другой. ===');
  process.exitCode = 1;
}
