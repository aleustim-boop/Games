// Проверка тестировщика: дверь «завершить» в общем листе «⋯» (js/лист-ещё.js),
// штаб/план-выход-из-партии.md, этап Э1.
// Запуск:
//   node tests/лист-ещё-завершить.js                  — обычный прогон, ждём 0 провалов
//   node tests/лист-ещё-завершить.js --файл <путь>    — тот же набор проверок, но код
//     js/лист-ещё.js берётся не с диска проекта, а из файла по указанному пути (для
//     ломающего запуска: путь ведёт на испорченную КОПИЮ во временной папке, файл
//     проекта эта проверка никогда не трогает и не портит).
//
// jsdom в проекте нет, а «активнаяДверьМеню»/«строкиЛиста» — чистые данные без DOM,
// их проверяем напрямую. Поведение кликов (открытие подтверждения, какая дверь
// сработала) требует настоящего document — вместо jsdom здесь лёгкий поддельный
// DOM: ровно те возможности, которыми пользуется js/лист-ещё.js (getElementById,
// createElement, classList, addEventListener/click, querySelector по одному классу,
// appendChild). Модуль загружается через vm из текста файла — так проверка работает
// и с настоящим js/лист-ещё.js, и с любой другой копией по пути --файл.

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const КОРЕНЬ = path.join(__dirname, '..');

function аргумент(имя) {
  const индекс = process.argv.indexOf(имя);
  return индекс !== -1 ? process.argv[индекс + 1] : null;
}

const путьКФайлу = аргумент('--файл') || path.join(КОРЕНЬ, 'js', 'лист-ещё.js');

/* ---------- лёгкий поддельный DOM ---------- */

/** Один элемент: то немногое, что использует js/лист-ещё.js.
 *  «реестр» — Map id -> элемент общего document (передаётся, чтобы сеттер id
 *  сразу регистрировал узел — как это молча делает настоящий браузер). */
function создатьЭлемент(тег, реестр) {
  const классы = new Set();
  const слушатели = {};
  const атрибуты = {};
  let _id = '';
  const эл = {
    tagName: тег,
    children: [],
    textContent: '',
    offsetParent: {},   // «видимый» узел — найтиОткрывающую() его находит
    classList: {
      add: function (c) { классы.add(c); },
      remove: function (c) { классы.delete(c); },
      contains: function (c) { return классы.has(c); },
      toggle: function (c, force) {
        const есть = классы.has(c);
        const нужно = force === undefined ? !есть : Boolean(force);
        if (нужно) классы.add(c); else классы.delete(c);
      }
    },
    setAttribute: function (k, v) { атрибуты[k] = String(v); },
    getAttribute: function (k) { return (k in атрибуты) ? атрибуты[k] : null; },
    addEventListener: function (тип, fn) { (слушатели[тип] = слушатели[тип] || []).push(fn); },
    click: function () { (слушатели.click || []).forEach(function (fn) { fn({}); }); },
    appendChild: function (реб) { эл.children.push(реб); return реб; },
    querySelector: function (sel) { return найтиПоКлассу(эл, sel.replace(/^\./, '').split(':')[0]); },
    focus: function () {}
  };
  Object.defineProperty(эл, 'id', {
    get: function () { return _id; },
    set: function (значение) { _id = значение; if (реестр) реестр.set(значение, эл); }
  });
  return эл;
}

function найтиПоКлассу(корень, класс) {
  for (let i = 0; i < корень.children.length; i++) {
    const реб = корень.children[i];
    if (реб.classList.contains(класс)) return реб;
    const вложенный = найтиПоКлассу(реб, класс);
    if (вложенный) return вложенный;
  }
  return null;
}

/** Поддельный document: getElementById — по реестру id (растёт при
 *  присвоении .id где угодно, не только внутри дерева — так же просто,
 *  как это делает настоящий браузер для любого узла в документе). */
function создатьDocument() {
  const реестр = new Map();
  const слушателиДокумента = {};
  const body = создатьЭлемент('body', реестр);

  return {
    body: body,
    createElement: function (тег) { return создатьЭлемент(тег, реестр); },
    getElementById: function (id) { return реестр.get(id) || null; },
    addEventListener: function (тип, fn) { (слушателиДокумента[тип] = слушателиДокумента[тип] || []).push(fn); },
    нажатьEscape: function () { (слушателиДокумента.keydown || []).forEach(function (fn) { fn({ key: 'Escape' }); }); },
    _зарегистрировать: function (id, эл) { реестр.set(id, эл); }
  };
}

/** Построить разметку одного листа «⋯» — те же id, что в index.html/нарды.html:
 *  кнопка «⋯», сам лист, фон, шесть строк (подпись «В меню» внутри первой). */
function построитьЛист(document) {
  const кнопкаЕщё = document.createElement('button');
  кнопкаЕщё.id = 'кнопка-игра-ещё';
  document.body.appendChild(кнопкаЕщё);

  const лист = document.createElement('div');
  лист.id = 'лист-игры';
  лист.classList.add('лист-ещё');
  лист.classList.add('скрыт');
  document.body.appendChild(лист);

  const фон = document.createElement('div');
  фон.id = 'лист-игры-фон';
  лист.appendChild(фон);

  function строка(id, подпись, idСостояния) {
    const кнопка = document.createElement('button');
    кнопка.id = id;
    кнопка.classList.add('лист-ещё__строка');
    лист.appendChild(кнопка);
    const текст = document.createElement('span');
    текст.classList.add('лист-ещё__подпись');
    текст.textContent = подпись;
    кнопка.appendChild(текст);
    if (idСостояния) {
      const состояние = document.createElement('span');
      состояние.id = idСостояния;
      состояние.classList.add('лист-ещё__значение');
      кнопка.appendChild(состояние);
    }
    return кнопка;
  }

  строка('кнопка-лист-игры-меню', 'В меню');
  строка('кнопка-лист-игры-правила', 'Как играть');
  строка('кнопка-лист-игры-звук', 'Звук', 'лист-игры-звук-состояние');
  строка('кнопка-лист-игры-вибрация', 'Вибрация', 'лист-игры-вибрация-состояние');
  строка('кнопка-лист-игры-оформление', 'Оформление');
  строка('кнопка-лист-игры-рекорды', 'Рекорды');

  const кнопкаЗакрыть = document.createElement('button');
  кнопкаЗакрыть.classList.add('лист-ещё__закрыть');
  лист.appendChild(кнопкаЗакрыть);
}

/** Загрузить js/лист-ещё.js как отдельный модуль из текста файла по «путьКФайлу»,
 *  с поддельным document в песочнице (та же схема, что в tests/проверка-нижних-вкладок.js,
 *  только сюда ещё добавлен document — коду подключить() он нужен для работы). */
function загрузитьЛистЕщё(document) {
  const исходник = fs.readFileSync(путьКФайлу, 'utf8');
  const модуль = { exports: {} };
  const песочница = { module: модуль, exports: модуль.exports, console: console, document: document };
  vm.createContext(песочница);
  vm.runInContext(исходник, песочница, { filename: путьКФайлу + ' (в памяти)' });
  return модуль.exports;
}

/* ---------- сами проверки ---------- */

function прогнатьПроверки() {
  const строки = [];
  let ошибок = 0;
  function проверка(имя, условие, подробности) {
    if (условие) {
      строки.push('OK   ' + имя);
    } else {
      ошибок++;
      строки.push('ПЛОХО ' + имя + (подробности ? ' — ' + подробности : ''));
    }
  }

  // --- Чистая логика без DOM: строкиЛиста()/активнаяДверьМеню() ---
  const document0 = создатьDocument();
  const ЛистЕщё = загрузитьЛистЕщё(document0);

  проверка('без двери «завершить»: строкиЛиста даёт «вМеню»',
    ЛистЕщё.строкиЛиста({ вМеню: { действие: function () {} } }).some(function (с) { return с.ключ === 'вМеню'; }));
  проверка('без двери «завершить»: строкиЛиста НЕ даёт «завершить»',
    !ЛистЕщё.строкиЛиста({ вМеню: { действие: function () {} } }).some(function (с) { return с.ключ === 'завершить'; }));

  const дверьЗавершитьИдёт = { действие: function () {}, видна: function () { return true; }, текст: 'т' };
  проверка('дверь «завершить» и партия идёт: строкиЛиста даёт «завершить»',
    ЛистЕщё.строкиЛиста({ вМеню: { действие: function () {} }, завершить: дверьЗавершитьИдёт })
      .some(function (с) { return с.ключ === 'завершить'; }));
  проверка('дверь «завершить» и партия идёт: строкиЛиста НЕ даёт «вМеню»',
    !ЛистЕщё.строкиЛиста({ вМеню: { действие: function () {} }, завершить: дверьЗавершитьИдёт })
      .some(function (с) { return с.ключ === 'вМеню'; }));

  const дверьЗавершитьНеИдёт = { действие: function () {}, видна: function () { return false; } };
  проверка('дверь «завершить» есть, но партия НЕ идёт: строкиЛиста даёт «вМеню» (совместимость)',
    ЛистЕщё.строкиЛиста({ вМеню: { действие: function () {} }, завершить: дверьЗавершитьНеИдёт })
      .some(function (с) { return с.ключ === 'вМеню'; }));

  проверка('строкиЛиста: строка меню — первая в списке (порядок не сломан)',
    ЛистЕщё.строкиЛиста({ вМеню: { действие: function () {} }, завершить: дверьЗавершитьИдёт })[0].ключ === 'завершить');

  // --- Поведение по клику: свежий document на каждый сценарий ---

  function собратьЛист(двери) {
    const document = создатьDocument();
    const МодульЛиста = загрузитьЛистЕщё(document);
    построитьЛист(document);
    const api = МодульЛиста.подключить({ двери: двери });
    return { document: document, api: api };
  }

  // Сценарий 1: без двери «завершить» — клик по «В меню» сразу зовёт дверь.действие(),
  // подтверждение не показывается вовсе.
  (function () {
    let действиеВызвано = false;
    const { document } = собратьЛист({ вМеню: { действие: function () { действиеВызвано = true; } } });
    document.getElementById('кнопка-лист-игры-меню').click();
    проверка('без двери «завершить»: клик «В меню» сразу зовёт дверь.действие()', действиеВызвано);
    const плашка = document.getElementById('плашка-завершить');
    проверка('без двери «завершить»: плашка подтверждения не появилась', плашка === null);
  })();

  // Сценарий 2: дверь «завершить» и партия идёт — клик по строке (подпись уже
  // «Завершить партию») открывает подтверждение, действие ещё НЕ вызвано.
  (function () {
    let действиеВызвано = false;
    let паузаВызвана = false;
    const { document, api } = собратьЛист({
      вМеню: { действие: function () {} },
      завершить: {
        действие: function () { действиеВызвано = true; },
        видна: function () { return true; },
        текст: 'Партия прервётся, в рекорды не попадёт',
        пауза: function () { паузаВызвана = true; }
      }
    });
    api.открыть();   // как открытие листа игроком — освежает подпись строки
    const подпись = document.getElementById('кнопка-лист-игры-меню').querySelector('.лист-ещё__подпись');
    проверка('партия идёт: подпись строки — «Завершить партию»',
      Boolean(подпись) && подпись.textContent === 'Завершить партию');

    document.getElementById('кнопка-лист-игры-меню').click();
    проверка('партия идёт, клик по строке: подтверждение открылось', !действиеВызвано);
    const плашка = document.getElementById('плашка-завершить');
    // Дальше — только если плашка вообще появилась: если её нет, обращаться
    // к её полям (querySelector, classList) уже некуда — это тоже провал,
    // просто печатаем его явно, не роняя весь прогон необработанным исключением.
    проверка('партия идёт, клик по строке: плашка «плашка-завершить» есть в DOM', плашка !== null);
    проверка('партия идёт, клик по строке: плашка видна (класс «скрыт» снят)',
      плашка !== null && !плашка.classList.contains('скрыт'));
    проверка('партия идёт, клик по строке: пауза вызвана', паузаВызвана);
    const текстПлашки = плашка && плашка.querySelector('.плашка-завершить__текст');
    проверка('плашка показывает текст последствия от игры',
      Boolean(текстПлашки) && текстПлашки.textContent === 'Партия прервётся, в рекорды не попадёт');

    // «Завершить» в плашке — зовёт дверь.действие(), плашка прячется.
    const кнопкаДа = плашка && плашка.querySelector('.плашка-завершить__да');
    if (кнопкаДа) кнопкаДа.click();
    проверка('кнопка «Завершить» в плашке зовёт дверь.действие()', Boolean(кнопкаДа) && действиеВызвано);
    проверка('после «Завершить» плашка снова скрыта', Boolean(плашка) && плашка.classList.contains('скрыт'));
  })();

  // Сценарий 3: «Вернуться к игре» — действие НЕ вызывается, продолжить() вызывается.
  (function () {
    let действиеВызвано = false;
    let продолжитьВызвано = false;
    const { document } = собратьЛист({
      завершить: {
        действие: function () { действиеВызвано = true; },
        видна: function () { return true; },
        текст: 'т',
        продолжить: function () { продолжитьВызвано = true; }
      }
    });
    document.getElementById('кнопка-лист-игры-меню').click();
    const плашка = document.getElementById('плашка-завершить');
    проверка('«Вернуться к игре» доступна: плашка открылась по клику строки', плашка !== null);
    const кнопкаНет = плашка && плашка.querySelector('.плашка-завершить__нет');
    if (кнопкаНет) кнопкаНет.click();
    проверка('кнопка «Вернуться к игре»: дверь.действие() НЕ вызвана', !действиеВызвано);
    проверка('кнопка «Вернуться к игре»: дверь.продолжить() вызвана', Boolean(кнопкаНет) && продолжитьВызвано);
    проверка('после «Вернуться к игре» плашка скрыта', Boolean(плашка) && плашка.classList.contains('скрыт'));
  })();

  return { строки: строки, ошибок: ошибок };
}

console.log('=== Проверка двери «завершить» в общем листе (файл: ' + путьКФайлу + ') ===');
const { строки, ошибок } = прогнатьПроверки();
строки.forEach(function (с) { console.log(с); });
console.log('');
console.log('Итого проверок: ' + строки.length + ', провалов: ' + ошибок);
process.exitCode = ошибок ? 1 : 0;
