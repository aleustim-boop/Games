/* ---------------- Подпись Telegram — по правилу сервера ---------------- */

function подписать(поля, токен) {
  const строки = Object.keys(поля)
    .filter(function (к) { return к !== 'hash'; })
    .map(function (к) { return к + '=' + поля[к]; })
    .sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(токен).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}

function подписьИгрока(номер, имя) {
  const поля = {
    query_id: 'AAF' + номер,
    user: JSON.stringify({ id: номер, first_name: имя, username: 'igrok' + номер }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  const сподписью = Object.assign({}, поля, { hash: подписать(поля, ТОКЕН_ДЛЯ_ПРОБЫ) });
  return Object.keys(сподписью)
    .map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(сподписью[к]); })
    .join('&');
}

/* ---------------- Разговор с дверями ---------------- */

function спросить(путь, тело) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН_АДРЕС, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (сбой) { разобрано = null; }
        готово({ код: ответ.statusCode, тело: разобрано || {}, текст: текст });
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

async function создатьСтол(кто, имя, ещё) {
  const тело = Object.assign({ initData: подписьИгрока(кто, имя), имя: имя }, ещё || {});
  const ответ = await спросить('/создать', тело);
  if (ответ.код !== 200 || !ответ.тело.код) {
    throw new Error('не вышло создать стол для ' + имя + ': ' + ответ.текст);
  }
  return { код: ответ.тело.код, пропуск: ответ.тело.пропуск, имя: имя, кто: кто };
}

async function войти(кто, имя, код) {
  const ответ = await спросить('/войти', { код: код, initData: подписьИгрока(кто, имя), имя: имя });
  if (ответ.код !== 200 || !ответ.тело.код) {
    throw new Error('не вышло войти в комнату ' + имя + ': ' + ответ.текст);
  }
  return { код: ответ.тело.код, пропуск: ответ.тело.пропуск, имя: имя, кто: кто };
}

function действие(стол, намерение) {
  return спросить('/ход', Object.assign({ код: стол.код, пропуск: стол.пропуск }, намерение));
}

function состояние(стол) {
  return спросить('/состояние', { код: стол.код, пропуск: стол.пропуск });
}

