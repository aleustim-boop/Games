// Проверка тестировщика: данные набора нижних вкладок (js/нижние-вкладки.js).
// Запуск: node tests/проверка-нижних-вкладок.js
// Смотрим только на чистые данные (вкладкиНабора) — без браузера, без DOM.
// Задача — поймать нарушение того, что просил владелец: одинаковые подписи
// и порядок «Игры/Лобби · Рейтинг · Профиль», отсутствие мёртвых вкладок.

const путь = require('path');
const НижниеВкладки = require(путь.join(__dirname, '..', 'js', 'нижние-вкладки.js'));

let ошибок = 0;
function проверка(имя, условие, подробности) {
  if (условие) {
    console.log('OK   ' + имя);
  } else {
    ошибок++;
    console.log('ПЛОХО ' + имя + (подробности ? ' — ' + подробности : ''));
  }
}

// --- Набор «витрина» ---
const витрина = НижниеВкладки.вкладкиНабора('витрина');
проверка('витрина: три вкладки', витрина.length === 3, 'получил ' + витрина.length);
проверка('витрина: подписи по порядку Игры/Рейтинг/Профиль',
  витрина.map(в => в.подпись).join('|') === 'Игры|Рейтинг|Профиль',
  витрина.map(в => в.подпись).join('|'));
проверка('витрина: активна ровно первая (Игры)',
  витрина[0].активна === true && витрина[1].активна === false && витрина[2].активна === false);
проверка('витрина: мёртвой вкладки «Друзья» нет',
  !витрина.some(в => в.подпись === 'Друзья'));
витрина.forEach(в => {
  проверка('витрина: у «' + в.подпись + '» есть либо id, либо действие (не мёртвая)',
    в.активна || !!в.id || !!в.действие);
  проверка('витрина: у «' + в.подпись + '» есть значок (не пустая строка)',
    typeof в.значок === 'string' && в.значок.length > 0);
});

// --- Набор «лобби-дурака» ---
const лобби = НижниеВкладки.вкладкиНабора('лобби-дурака');
проверка('лобби: три вкладки', лобби.length === 3, 'получил ' + лобби.length);
проверка('лобби: подписи по порядку Лобби/Рейтинг/Профиль',
  лобби.map(в => в.подпись).join('|') === 'Лобби|Рейтинг|Профиль',
  лобби.map(в => в.подпись).join('|'));
проверка('лобби: активна ровно первая (Лобби)',
  лобби[0].активна === true && лобби[1].активна === false && лобби[2].активна === false);
лобби.forEach(в => {
  проверка('лобби: у «' + в.подпись + '» есть либо id, либо действие (не мёртвая)',
    в.активна || !!в.id || !!в.действие);
});
проверка('лобби: id вкладки «Рейтинг» — старое имя «лобби-вкладка-рейтинг»',
  лобби[1].id === 'лобби-вкладка-рейтинг', лобби[1].id);
проверка('лобби: id вкладки «Профиль» — старое имя «лобби-вкладка-профиль»',
  лобби[2].id === 'лобби-вкладка-профиль', лобби[2].id);

// --- Неизвестный набор не должен падать, а должен тихо отдавать пустоту ---
const пусто = НижниеВкладки.вкладкиНабора('такого-набора-не-бывает');
проверка('неизвестный набор: пустой список, а не исключение', Array.isArray(пусто) && пусто.length === 0);

// --- Сборка HTML одной кнопки не должна падать на всех вкладках обоих наборов ---
[...витрина, ...лобби].forEach(в => {
  let html = '';
  let упало = false;
  try { html = НижниеВкладки.кнопкаHTML(в); } catch (e) { упало = true; }
  проверка('кнопкаHTML не падает для «' + в.подпись + '»', !упало);
  проверка('кнопкаHTML для «' + в.подпись + '» содержит подпись в тексте',
    html.indexOf('>' + в.подпись + '<') !== -1, html);
});

console.log('');
if (ошибок === 0) {
  console.log('ИТОГ: все проверки прошли (' + (витрина.length + лобби.length + 2) + ' вкладок и наборов проверено)');
  process.exit(0);
} else {
  console.log('ИТОГ: найдено проблем — ' + ошибок);
  process.exit(1);
}
