/* ---------------------------- Г. Уход ---------------------------- */
async function уход() {
  console.log('\nГ. /турнир-уйти');
  // Аня снова на экране турнира, потом уходит.
  await спросить('/турнир-новости', { initData: подпись(АНЯ, 'Аня') }, 'POST', 600);
  const уйти = await спросить('/турнир-уйти', { initData: подпись(АНЯ, 'Аня') });
  проверить(уйти.код === 200 && уйти.тело.ок === true && Object.keys(уйти.тело).join(',') === 'ок',
    'уход: {ок:true} (' + уйти.текст + ')');
  // Боря ждёт пару: ушедшую Аню ему не дают.
  const новости = await ждатьНовостей(БОРЯ, 'Боря', 5000);
  проверить(новости === null, 'ушедшая пары не получила (' + (новости ? новости.текст : 'ничего') + ')');
  const сводка = await спросить('/турнир', { initData: подпись(АНЯ, 'Аня') });
  проверить(сводка.тело.вид && сводка.тело.вид.записан === true, 'запись после ухода осталась');

  // Аня вернулась на экран: она не «вечно занята» — пара находится.
  const вернулась = await параСнова('вернулась после ухода');
  if (!вернулась) return;

  /* Создание стола один раз бросает: пара обязана вернуться в ожидание и
     сесть следующим шагом, а не застрять «занятой». Подменяем свойство
     модуля комнат (сервер зовёт его через комнаты.создатьСтолТурнира). */
  const настоящий = комнаты.создатьСтолТурнира;
  let бросков = 0;
  комнаты.создатьСтолТурнира = function () {
    if (бросков === 0) { бросков++; throw new Error('проверочный бросок'); }
    return настоящий.apply(this, arguments);
  };
  try {
    await параСнова('после брошенного создания стола');
  } finally {
    комнаты.создатьСтолТурнира = настоящий;
  }
  проверить(бросков === 1, 'создание стола действительно бросило один раз (' + бросков + ')');
}

/** Аня и Боря ждут пару вместе → один стол → Аня сдаётся. Вернёт true, если сели. */
async function параСнова(когда) {
  const [н1, н2] = await Promise.all([
    ждатьНовостей(АНЯ, 'Аня', 8000),
    ждатьНовостей(БОРЯ, 'Боря', 8000)
  ]);
  const а = н1 ? н1.тело : {};
  const б = н2 ? н2.тело : {};
  const сели = а.статус === 'посадили' && б.статус === 'посадили' && а.код === б.код;
  проверить(сели, когда + ': Аня и Боря снова за одним столом (' + JSON.stringify(а.статус) + ', ' + JSON.stringify(б.статус) + ')');
  if (!сели) return false;
  const выход = await спросить('/выйти', { код: а.код, пропуск: а.пропуск });
  проверить(выход.код === 200, когда + ': Аня сдалась');
  await пауза(400);
  return true;
}

/* ------------------------- Д. Запасная личина ------------------------- */
async function запаснаяЛичина() {
  console.log('\nД. Запасная личина одиночке');
  // Боря и Аня пропадают со связи: их «на экране» старше 10 с.
  сдвиг += 15000;
  const запись = await спросить('/турнир-записаться', { initData: подпись(ВИТЯ, 'Витя') });
  проверить(запись.тело.ок === true, 'Витя записался');
  /* Первое создание стола с личиной бросает: Витя обязан остаться ждать и
     сесть следующим шагом, а шаг турнира — не оборваться сбоем (в журнале
     нет «шаг не удался»). Журнал слушаем, не глуша его. */
  const настоящий = комнаты.создатьСтолТурнира;
  let бросковЛичины = 0;
  комнаты.создатьСтолТурнира = function (игра, участники) {
    if (бросковЛичины === 0 && участники && участники[1] && участники[1].личина) {
      бросковЛичины++;
      throw new Error('проверочный бросок с личиной');
    }
    return настоящий.apply(this, arguments);
  };
  const прежнийError = console.error;
  const журнал = [];
  console.error = function () {
    журнал.push(Array.prototype.join.call(arguments, ' '));
    return прежнийError.apply(console, arguments);
  };
  // Часы бегут вперёд по 2 с за четверть секунды: 90 с ожидания — за ~12 с.
  const часы = setInterval(function () { сдвиг += 2000; }, 250);
  let новости;
  try {
    новости = await ждатьНовостей(ВИТЯ, 'Витя', 25000);
  } finally {
    clearInterval(часы);
    комнаты.создатьСтолТурнира = настоящий;
    console.error = прежнийError;
  }
  const н = новости ? новости.тело : {};
  проверить(бросковЛичины === 1, 'создание стола с личиной действительно бросило один раз (' + бросковЛичины + ')');
  const сбоиШага = журнал.filter(с => /Турнир: шаг не удался/.test(с));
  проверить(сбоиШага.length === 0, 'брошенная посадка к личине не обрывает шаг турнира (в журнале: ' + JSON.stringify(сбоиШага[0] || '') + ')');
  const живой = await спросить('/здоровье', null, 'GET');
  проверить(живой.код === 200 && живой.тело.живой === true, 'после броска с личиной сервер жив');
  проверить(н.статус === 'посадили', 'Вите посадили соперника (' + JSON.stringify(н.статус) + ')');
  if (н.статус !== 'посадили') return;
  const место = комнаты.найтиИгрока(н.код, н.пропуск);
  const соседи = место ? Object.keys(место.комната.игроки).filter(к => к !== место.ктоЯ).map(к => место.комната.игроки[к]) : [];
  проверить(соседи.length === 1 && соседи[0].личина && личины.этоЛичина(соседи[0].личина.номер),
    'напротив Вити — личина');
  const выход = await спросить('/выйти', { код: н.код, пропуск: н.пропуск });
  проверить(выход.код === 200, 'Витя сдался');
  await пауза(300);
  const сводка = await спросить('/турнир', { initData: подпись(ВИТЯ, 'Витя') });
  const таблица = (сводка.тело.вид && сводка.тело.вид.таблица) || [];
  const витя = таблица.find(с => с.имя === 'Витя');
  проверить(Boolean(витя) && витя.очки === 0 && витя.партий === 1, 'у Вити в таблице 0 очков за 1 партию');
  const имена = таблица.map(с => с.имя);
  проверить(таблица.length === 3 && имена.every(и => ['Аня', 'Боря', 'Витя'].indexOf(и) !== -1),
    'в таблице только люди (' + JSON.stringify(имена) + ')');
  const номера = турниры.участники(идТурнира()).map(у => у.номер);
  проверить(номера.length === 3 && номера.every(н2 => !личины.этоЛичина(н2)), 'личины нет среди участников (' + номера.length + ')');
}

