/** Кнопка письма ведёт на экран турнира нашего сайта. */
function кнопкаНаТурнир(письмо) {
  const кнопка = письмо && письмо.reply_markup && письмо.reply_markup.inline_keyboard &&
    письмо.reply_markup.inline_keyboard[0] && письмо.reply_markup.inline_keyboard[0][0];
  return Boolean(кнопка && кнопка.web_app &&
    кнопка.web_app.url === АДРЕС_САЙТА + '/index.html#' + encodeURIComponent('турнир'));
}

/** Первый момент после начала, когда турнир дня «окончен» (по модулю, без своих чисел). */
function когдаОкончен(день) {
  let мс = день.конецМс;
  while (турниры.турнирДня(мс).состояние !== 'окончен') мс += МИНУТА;
  return мс;
}

