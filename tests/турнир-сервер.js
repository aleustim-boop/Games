function подписать(поля) {
  const строки = Object.keys(поля).map(function (к) { return к + '=' + поля[к]; }).sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(ТОКЕН).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}
function подпись(номер, имя) {
  const поля = {
    query_id: 'AAF' + номер,
    user: JSON.stringify({ id: номер, first_name: имя }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  const всё = Object.assign({}, поля, { hash: подписать(поля) });
  return Object.keys(всё).map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(всё[к]); }).join('&');
}

/* Все ответы дверей турнира — для проверки «номеров наружу нет». */
const ответыТурнира = [];

/** Запрос к своему серверу. срокМс — оборвать долгий опрос (ответ {код:0}). */
function спросить(путь, тело, метод, срокМс) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    let оборван = false;
    const запрос = http.request({
      host: АДРЕС, port: ПОРТ, path: encodeURI(путь), method: метод || 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': метод === 'GET' ? 0 : данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (к) { текст += к; });
      ответ.on('end', function () {
        if (оборван) return;
        clearTimeout(таймер);
        let разобрано = {}; try { разобрано = JSON.parse(текст || '{}'); } catch (с) { /* пусто */ }
        if (путь.indexOf('/турнир') === 0) ответыТурнира.push(текст);
        готово({ код: ответ.statusCode, тело: разобрано, текст: текст });
      });
    });
    const таймер = срокМс ? setTimeout(function () {
      оборван = true;
      запрос.destroy();
      готово({ код: 0, тело: {}, текст: '' });
    }, срокМс) : null;
    запрос.on('error', function (с) { if (!оборван) беда(с); });
    if (метод !== 'GET') запрос.write(данные);
    запрос.end();
  });
}

/** Опрашивать /турнир-новости, пока не придёт изменение или не выйдет срок. */
async function ждатьНовостей(номер, имя, срокМс, приКаждом) {
  const конец = Date.now() + срокМс;
  while (Date.now() < конец) {
    const ответ = await спросить('/турнир-новости', { initData: подпись(номер, имя) }, 'POST',
      Math.min(1500, Math.max(50, конец - Date.now())));
    if (ответ.код === 200 && ответ.тело.изменилось === true) return ответ;
    if (приКаждом) приКаждом();
  }
  return null;
}

