#!/usr/bin/env node
'use strict';

/* =====================================================================
   ДУРАК: КОНЕЦ ПО СОГЛАСИЮ В ВИДЕ ДЛЯ ИГРОКА (этап Э3 плана
   штаб/план-дурак-согласие.md).

   Что проверяет. Когда стол закончил партию по согласию, сервер ставит
   партия.законченаПоСогласию = true, в проигравшие кладёт только ушедших
   (сдавшихся), а скинувших карты до согласия — в партия.победителиПоСогласию
   (это заполнит сервер на этапе Э2; здесь кладём руками). Сетевой слой
   (видДляИгрока в server/партия-по-сети.js) обязан:
     1) всегда давать вид.поСогласию — true при согласии, false иначе;
     2) итог: «поражение» сдавшимся, «победа» местам из победителиПоСогласию,
        остальным null (а не «победа» всем, кто не проиграл, как при картах);
     3) не ставить итог «соперник-ушёл» при согласии;
     4) обычный конец по картам — без перемен: поСогласию false, итог прежний.

   Партии собираются через начатьПартию (тот же путь, каким раздаёт комната),
   поля конца проставляются руками — так, как их ставит сервер.

   ЛОМАЮЩИЙ ЗАПУСК: node tests/дурак-согласие-вид.js --сломать N
   Копия server/ и js/ во временной папке, файл проекта не трогается:
     1 — в копии нет строки вид.поСогласию;
     2 — в копии итог при согласии «победа» всем;
     3 — в копии «соперник-ушёл» ставится и при согласии.
   Каждая порча обязана дать провал (выход 1). Строка для порчи не нашлась —
   выход 2: код изменился, проверку надо поправить, а не верить зелёному.

   Запуск:
     node tests/дурак-согласие-вид.js              обычный прогон, всё зелёное
     node tests/дурак-согласие-вид.js --сломать 2  порча №2, ждём красного
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');

/* Порчи: что ищем в копии server/партия-по-сети.js и на что меняем. */
const ПОРЧИ = {
  1: {
    что: 'нет строки вид.поСогласию',
    шаблон: /вид\.поСогласию\s*=\s*партия\.законченаПоСогласию\s*===\s*true;/,
    замена: '/* ИСПОРЧЕНО: вид.поСогласию не пишется */'
  },
  2: {
    что: 'итог при согласии — «победа» всем',
    шаблон: /if \(партия\.законченаПоСогласию === true\) return итогПоСогласию\(партия, ктоЯ\);/,
    замена: "if (партия.законченаПоСогласию === true) return 'победа';"
  },
  3: {
    что: '«соперник-ушёл» и при согласии',
    шаблон: / && !вид\.поСогласию\) вид\.итог = 'соперник-ушёл';/,
    замена: ") вид.итог = 'соперник-ушёл';"
  }
};

function номерПорчи() {
  const где = process.argv.indexOf('--сломать');
  if (где === -1) return null;
  const номер = process.argv[где + 1];
  if (!ПОРЧИ[номер]) {
    console.log('Неизвестная порча «' + номер + '». Есть: ' + Object.keys(ПОРЧИ).join(', '));
    process.exit(2);
  }
  return номер;
}

/** Своя копия server/ и js/ во временной папке, в ней портим одну строку. */
function подготовитьСломаннуюКопию(номер) {
  const порча = ПОРЧИ[номер];
  const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'дурак-согласие-вид-'));
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(врем, 'server'), { recursive: true });
  require('./пути-проекта.js').скопироватьКод(КОРЕНЬ, врем, 'js');
  const путь = path.join(врем, 'server', 'партия-по-сети.js');
  const исходник = fs.readFileSync(путь, 'utf8');
  if (!порча.шаблон.test(исходник)) {
    console.log('  БЕДА ломать нечего: для порчи №' + номер + ' строка не найдена — код изменился, поправьте tests/дурак-согласие-вид.js');
    process.exit(2);
  }
  fs.writeFileSync(путь, исходник.replace(порча.шаблон, порча.замена), 'utf8');
  return врем;
}

const ПОРЧА = номерПорчи();
const ПАПКА = ПОРЧА ? подготовитьСломаннуюКопию(ПОРЧА) : КОРЕНЬ;
if (ПОРЧА) {
  console.log('Ломающий прогон №' + ПОРЧА + ' (' + ПОРЧИ[ПОРЧА].что + ') — ждём провала.');
  process.on('exit', function () {
    try { fs.rmSync(ПАПКА, { recursive: true, force: true }); } catch (сбой) { /* не страшно */ }
  });
}

const сеть = require(path.join(ПАПКА, 'server', 'партия-по-сети.js'));
console.log('Сеть-слой из: ' + ПАПКА);

let проверок = 0;
let провалов = 0;
function проверить(условие, что) {
  проверок++;
  if (условие) {
    console.log('  ✓ ' + что);
  } else {
    провалов++;
    console.log('  ✗ ПРОВАЛ: ' + что);
  }
}

const МЕСТА = сеть.МЕСТА.slice(0, 4);
const [А, Б, В, Г] = МЕСТА;
// Ноль мест — проверка ни о чём: краснеем сразу.
проверить(МЕСТА.length === 4 && МЕСТА.every(Boolean), 'за столом четыре места');

function новаяПартия(парами) {
  return сеть.начатьПартию(null, { игроки: МЕСТА.slice(), парами: парами === true });
}

/** Партия, законченная по согласию так, как это делает сервер. */
function партияПоСогласию(сдавшиеся, победители, парами) {
  const партия = новаяПартия(парами);
  партия.завершена = true;
  партия.законченаПоСогласию = true;
  партия.ничья = false;
  партия.проигравшие = сдавшиеся.slice();
  партия.результат = сдавшиеся.length > 0 ? сдавшиеся.join(' и ') : null;
  if (победители !== undefined) партия.победителиПоСогласию = победители.slice();
  return партия;
}

/** Сверить у каждого места поСогласию и итог с ожиданием. */
function сверитьСтол(партия, ждёмПоСогласию, ждёмИтог, добавка) {
  for (const место of МЕСТА) {
    const вид = сеть.видДляИгрока(партия, место, добавка ? Object.assign({}, добавка) : {});
    проверить(вид.поСогласию === ждёмПоСогласию,
      'место ' + место + ': поСогласию === ' + ждёмПоСогласию + ' (есть: ' + вид.поСогласию + ')');
    проверить(вид.итог === ждёмИтог[место],
      'место ' + место + ': итог ' + JSON.stringify(ждёмИтог[место]) + ' (есть: ' + JSON.stringify(вид.итог) + ')');
  }
}

function итоги(а, б, в, г) {
  return { [А]: а, [Б]: б, [В]: в, [Г]: г };
}

console.log('\n1) Все согласились, никто не уходил: итога нет ни у кого');
сверитьСтол(партияПоСогласию([], []), true, итоги(null, null, null, null));

console.log('\n1а) То же, но в обёртке «соперникУшёл» (один человек с ботами) — не «соперник-ушёл»');
сверитьСтол(партияПоСогласию([], []), true, итоги(null, null, null, null), { соперникУшёл: true });

console.log('\n2) Согласились после ухода Б: Б — поражение, прочим ничего (списка победителей нет вовсе)');
сверитьСтол(партияПоСогласию([Б], undefined), true, итоги(null, 'поражение', null, null));

console.log('\n3) А пропал (место отдали боту), потом стол согласился: А — поражение');
сверитьСтол(партияПоСогласию([А], []), true, итоги('поражение', null, null, null));

console.log('\n4) А скинул все карты, потом согласились: А — победа, прочим ничего');
сверитьСтол(партияПоСогласию([], [А]), true, итоги('победа', null, null, null));

console.log('\n4а) А скинул карты, В ушёл, потом согласились: А — победа, В — поражение');
сверитьСтол(партияПоСогласию([В], [А]), true, итоги('победа', null, 'поражение', null));

console.log('\n5) Игра парами: Б ушёл, стол согласился — победы нет ни у кого');
const парная = партияПоСогласию([Б], [], true);
проверить(парная.парами === true, 'партия и правда парами');
сверитьСтол(парная, true, итоги(null, 'поражение', null, null));

console.log('\n6) Обычный конец по картам: Г — дурак, остальные выиграли');
const обычная = новаяПартия();
обычная.завершена = true;
обычная.проигравшие = [Г];
обычная.результат = Г;
сверитьСтол(обычная, false, итоги('победа', 'победа', 'победа', 'поражение'));

console.log('\n7) Соперник ушёл совсем (без согласия): итог прежний «соперник-ушёл»');
const брошенная = новаяПартия();
брошенная.завершена = true;
брошенная.проигравшие = [];
брошенная.результат = null;
сверитьСтол(брошенная, false,
  итоги('соперник-ушёл', 'соперник-ушёл', 'соперник-ушёл', 'соперник-ушёл'), { соперникУшёл: true });

console.log('\n8) Партия идёт: поСогласию честно false, итога нет');
сверитьСтол(новаяПартия(), false, итоги(null, null, null, null));

console.log('');
console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
process.exit(провалов > 0 ? 1 : 0);
