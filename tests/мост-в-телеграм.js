'use strict';
/* =====================================================================
   ПРОВЕРКА МОСТА В TELEGRAM (js/мост-в-телеграм.js), без браузера.

   Что проверяем:
   1. Модуль подключён на всех восьми страницах (index, деберц, домино,
      монополия, морской-бой, нарды, шахматы, шашки).
   2. Ссылка в модуле ровно https://t.me/BoardingGames_bot?start=src_site,
      а метка «site» проходит шаблон бота (МЕТКА_ССЫЛКИ из
      bot/статистика.js — читаем из файла, своей копии шаблона нет) и
      разбор команды «/start src_site» в bot/бот.js.
   3. В js нет style.* = и setAttribute('style') — вид только классами.
   4. Поведение в песочнице vm с поддельной страницей: вне Telegram
      карточка вставлена (на витрине — перед списком игр, в лобби —
      перед нижней полосой), с подписью initData — не вставлена вовсе.

   Запуск:            node tests/мост-в-телеграм.js
   Ломающий запуск:   node tests/мост-в-телеграм.js --сломать <путь к копии модуля>
   Копию портит и кладёт тот, кто запускает, во временную папку; файл
   проекта не трогаем. Проверка обязана покраснеть.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const КОРЕНЬ = path.join(__dirname, '..');
const индексСломанного = process.argv.indexOf('--сломать');
const ПУТЬ_МОДУЛЯ = индексСломанного === -1
  ? path.join(КОРЕНЬ, 'js', 'мост-в-телеграм.js')
  : process.argv[индексСломанного + 1];

if (индексСломанного !== -1) {
  if (!ПУТЬ_МОДУЛЯ || path.resolve(ПУТЬ_МОДУЛЯ).startsWith(path.resolve(КОРЕНЬ) + path.sep)) {
    console.error('Для --сломать нужен путь к копии ВНЕ папки проекта (например в %TEMP%).');
    process.exit(2);
  }
}

const СТРАНИЦЫ = ['index', 'деберц', 'домино', 'монополия', 'морской-бой', 'нарды', 'шахматы', 'шашки'];
const ОЖИДАЕМАЯ_ССЫЛКА = 'https://t.me/BoardingGames_bot?start=src_site';

let всего = 0;
let провалов = 0;
function проверка(имя, условие, подробность) {
  всего++;
  if (!условие) {
    провалов++;
    console.log('  ПРОВАЛ: ' + имя + (подробность ? ' — ' + подробность : ''));
  } else {
    console.log('  ок: ' + имя);
  }
}

const текстМодуля = fs.readFileSync(ПУТЬ_МОДУЛЯ, 'utf8');

// 1. Подключение на страницах
console.log('1. Подключение на страницах');
for (const страница of СТРАНИЦЫ) {
  const html = fs.readFileSync(path.join(КОРЕНЬ, страница + '.html'), 'utf8');
  const найдено = html.match(/<script src="js\/мост-в-телеграм\.js\?v=\d+"><\/script>/g) || [];
  проверка(страница + '.html: ровно одно подключение', найдено.length === 1, 'найдено ' + найдено.length);
}

// 2. Ссылка и шаблон бота
console.log('2. Ссылка и метка');
const найденныеСсылки = текстМодуля.match(/https:\/\/t\.me\/[^'"\s]+/g) || [];
проверка('в модуле одна ссылка на бота', найденныеСсылки.length === 1, 'найдено ' + найденныеСсылки.length);
проверка('ссылка ровно ' + ОЖИДАЕМАЯ_ССЫЛКА, найденныеСсылки[0] === ОЖИДАЕМАЯ_ССЫЛКА, String(найденныеСсылки[0]));

const текстСтатистики = fs.readFileSync(path.join(КОРЕНЬ, 'bot', 'статистика.js'), 'utf8');
const шаблонИзФайла = /const МЕТКА_ССЫЛКИ = \/(.+)\/;/.exec(текстСтатистики);
проверка('в bot/статистика.js найден шаблон МЕТКА_ССЫЛКИ', !!шаблонИзФайла);
const метка = /[?&]start=src_([^&'"\s]+)/.exec(найденныеСсылки[0] || '');
проверка('в ссылке есть start=src_<метка>', !!метка);
if (шаблонИзФайла && метка) {
  проверка('метка «' + метка[1] + '» проходит шаблон бота', new RegExp(шаблонИзФайла[1]).test(метка[1].toLowerCase()));
  проверка('метка равна «site»', метка[1] === 'site');
}
const текстБота = fs.readFileSync(path.join(КОРЕНЬ, 'bot', 'бот.js'), 'utf8');
const разборБота = /const разбор = (\/.+\/)\.exec\(текст\);/.exec(текстБота);
проверка('в bot/бот.js найден разбор «/start src_…»', !!разборБота);
if (разборБота) {
  // Шаблон — литерал вида /^\/start(@\S+)?\s+src_(\S+)$/ — собираем из текста файла.
  const регулярка = vm.runInNewContext(разборБота[1]);
  const разобрано = регулярка.exec('/start src_site');
  проверка('бот разбирает «/start src_site» как метку site', !!разобрано && разобрано[2] === 'site');
}

// 3. Вид не из js
console.log('3. Вид только классами');
проверка('нет .style. и cssText', !/\.style\b|cssText/.test(текстМодуля));
проверка('нет setAttribute(\'style\')', !/setAttribute\(\s*['"]style['"]/.test(текстМодуля));
проверка('нет style="…" в разметке', !/\sstyle\s*=/.test(текстМодуля));

// 4. Поведение в песочнице
console.log('4. Поведение в песочнице');

/** Поддельная страница: считаем, куда вставили карточку. */
function запустить(настройки) {
  const вставки = [];
  function элемент(имя) {
    return {
      имя: имя,
      className: '',
      innerHTML: '',
      children: [],
      classList: { contains: function (к) { return (this.владелец.className || '').split(' ').indexOf(к) !== -1; } },
      setAttribute: function () {},
      parentNode: null,
      insertBefore: function (новый, перед) { вставки.push({ родитель: this.имя, перед: перед && перед.имя }); новый.parentNode = this; this.вставлен = новый; },
      appendChild: function (новый) { вставки.push({ родитель: this.имя, перед: null }); this.вставлен = новый; }
    };
  }
  function сКлассом(имя, класс) {
    const э = элемент(имя);
    э.className = класс;
    э.classList.владелец = э;
    return э;
  }
  const вставленные = [];
  const документ = {
    readyState: 'complete',
    addEventListener: function () {},
    createElement: function () { const э = сКлассом('карточка', ''); вставленные.push(э); return э; },
    querySelector: function (селектор) {
      if (селектор === '.витрина__плитки' && настройки.витрина) {
        const плитки = сКлассом('плитки', 'витрина__плитки');
        плитки.parentNode = сКлассом('витрина', '');
        настройки.плитки = плитки;
        return плитки;
      }
      if (селектор === '.мост-в-телеграм') {
        return вставленные.filter(function (э) { return э.className === 'мост-в-телеграм'; })[0] || null;
      }
      return null;
    },
    getElementById: function (id) {
      if (id === 'экран-витрины') return настройки.витрина ? сКлассом('экран-витрины', '') : null;
      if (id === 'экран-лобби' && !настройки.витрина) {
        const лобби = сКлассом('лобби', '');
        лобби.children = [сКлассом('входы', ''), сКлассом('полоса', 'нижние-вкладки')];
        return лобби;
      }
      return null;
    }
  };
  const окно = {
    document: документ,
    location: { hash: настройки.хеш || '' },
    sessionStorage: { getItem: function () { return null; } },
    Telegram: настройки.подпись ? { WebApp: { initData: 'query_id=AAA&hash=bbb', platform: 'android' } } : { WebApp: { initData: '', platform: 'unknown' } }
  };
  окно.window = окно;
  try {
    vm.runInNewContext(текстМодуля, окно, { filename: ПУТЬ_МОДУЛЯ });
  } catch (ошибка) {
    проверка('модуль выполняется без ошибок', false, ошибка.message);
  }
  const карточка = вставленные.filter(function (э) { return э.className === 'мост-в-телеграм'; })[0];
  return { вставки: вставки, карточка: карточка };
}

const гостьВитрина = запустить({ витрина: true });
проверка('витрина, гость: карточка создана', !!гостьВитрина.карточка);
проверка('витрина, гость: вставлена перед списком игр', гостьВитрина.вставки.length === 1 && гостьВитрина.вставки[0].перед === 'плитки');
проверка('карточка содержит «Играйте в Telegram»', !!гостьВитрина.карточка && гостьВитрина.карточка.innerHTML.indexOf('Играйте в Telegram') !== -1);
проверка('карточка содержит «Открыть в Telegram» и target=_blank rel=noopener',
  !!гостьВитрина.карточка && /Открыть в Telegram/.test(гостьВитрина.карточка.innerHTML) &&
  /target="_blank"/.test(гостьВитрина.карточка.innerHTML) && /rel="noopener"/.test(гостьВитрина.карточка.innerHTML));
проверка('карточка содержит ссылку ?start=src_site', !!гостьВитрина.карточка && гостьВитрина.карточка.innerHTML.indexOf(ОЖИДАЕМАЯ_ССЫЛКА) !== -1);

const гостьЛобби = запустить({ витрина: false });
проверка('лобби, гость: карточка вставлена перед нижней полосой', !!гостьЛобби.карточка && гостьЛобби.вставки.length === 1 && гостьЛобби.вставки[0].перед === 'полоса');

const вTelegramВитрина = запустить({ витрина: true, подпись: true });
проверка('витрина, Telegram с подписью: карточки нет, вставок нет', !вTelegramВитрина.карточка && вTelegramВитрина.вставки.length === 0);
const вTelegramЛобби = запустить({ витрина: false, подпись: true });
проверка('лобби, Telegram с подписью: карточки нет, вставок нет', !вTelegramЛобби.карточка && вTelegramЛобби.вставки.length === 0);
const поАдресу = запустить({ витрина: true, хеш: '#tgWebAppData=abc&tgWebAppPlatform=ios' });
проверка('витрина, признак Telegram в адресе: карточки нет', !поАдресу.карточка && поАдресу.вставки.length === 0);

console.log('Итого проверок: ' + всего + ', провалов: ' + провалов);
process.exit(провалов > 0 ? 1 : 0);
