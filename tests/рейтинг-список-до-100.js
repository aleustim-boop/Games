/* Проверка слов владельца 25.09: под подиумом список идёт сразу до
   100 строк всего (подиум + до 97 строк ниже), без подписей «Все игроки
   показаны» / «Показаны первые N» и без кнопки «Показать ещё» — новые
   строки докатываются сами тем же курсором сервера, что раньше открывала
   кнопка (js/рейтинг-экран.js, «пределСпискаПодПодиумом» и
   «довезтиСписокДоПредела»).

   Песочница vm по образцу tests/рейтинг-партия-5.js и
   tests/рейтинг-страница-2-экран.js — без браузера: проверка смотрит
   только на структуру DOM и тексты, не на пиксели, поэтому Playwright
   не нужен (правило проекта «сперва скрипт, браузер по остатку»).

   Поддельный fetch ведёт себя как server/рейтинг.js: первый запрос без
   «продолжение» отдаёт верхушку до 25 строк и курсор «продолжение»;
   повторные запросы с «продолжение» отдают страницу не больше 50 строк
   за раз (тот же потолок, что серверная «СТРАНИЦА_ПОТОЛОК») и новый
   курсор — строку, если список ещё не кончился, иначе null.

   Сценарии:
   1. 150 игроков — на подиуме ровно 3 карточки, под ним ровно 97 строк
      (100 − 3), подписей «Все игроки показаны» / «Показаны первые» нет,
      кнопки «Показать ещё» нет.
   2. 5 игроков — на подиуме 3, под ним 2 строки, тех же подписей и
      кнопки тоже нет.

   Ломающий запуск --сломать: портит КОПИЮ js/рейтинг-экран.js во
   временной папке (файл проекта не трогаем) — «довезтиСписокДоПредела»
   выходит сразу же, ни одного дозапроса больше не делает. У 150 игроков
   список останавливается на 22 строках (верхушка без подиума) вместо 97 —
   ожидаемо краснеет проверка «под подиумом ровно 97 строк». */

const fs = require('fs');
const os = require('os');
const path = require('path');
const бр = require(path.join(__dirname, 'поддельный-браузер.js'));

const КОРЕНЬ = path.join(__dirname, '..');
const FILE_ARG = process.argv.find(function (д) { return д.indexOf('--файл=') === 0; });
const файлРейтинга = FILE_ARG ? FILE_ARG.split('=')[1] : path.join(КОРЕНЬ, 'js', 'рейтинг-экран.js');
const исходник = fs.readFileSync(файлРейтинга, 'utf8');

const СЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;
let исходникРабочий = исходник;

if (СЛОМАТЬ) {
  const ИСКОМОЕ = 'if (!вид || соседи || догрузкаИдёт || догрузкаСбоила) return;';
  if (исходник.indexOf(ИСКОМОЕ) === -1) {
    console.log('ОШИБКА: приём порчи --сломать устарел (устройство изменилось) — ' +
      'не нашлась искомая строка в ' + файлРейтинга);
    process.exit(1);
  }
  const испорченный = исходник.split(ИСКОМОЕ).join(
    'if (true) return; /* порчено --сломать: автодогрузка списка до 100 строк выключена */'
  );
  const файлКопии = path.join(os.tmpdir(), 'рейтинг-экран-испорчен-до-100-' + Date.now() + '.js');
  fs.writeFileSync(файлКопии, испорченный, 'utf8');
  исходникРабочий = fs.readFileSync(файлКопии, 'utf8');
  console.log('Ломающий запуск --сломать: порчу КОПИЮ в ' + файлКопии + ' (файл проекта не трогаю) —');
  console.log('  «довезтиСписокДоПредела» выходит сразу, докатка до 100 строк не работает.');
  console.log('');
}

let провалов = 0;
let всегоПроверок = 0;

function проверить(имя, годно, деталь) {
  всегоПроверок += 1;
  console.log((годно ? '  ok    — ' : ' ПРОВАЛ — ') + имя + (деталь ? ' (' + деталь + ')' : ''));
  if (!годно) провалов += 1;
}

function ждать(мс) { return new Promise(function (r) { setTimeout(r, мс || 15); }); }

function игрок(место) {
  return {
    место: место,
    имя: 'Игрок ' + место,
    очки: 100000 - место * 10,
    побед: место,
    партий: место + 5,
    этоЯ: false
  };
}

/* Поддельный сервер: первый запрос — верхушка до 25 строк и курсор,
   дальше — страницы по курсору не больше 50 строк за раз, та же
   логика, что «ВЕРХУШКИ»/«СТРАНИЦА_ПОТОЛОК» в server/рейтинг.js. */
function сделатьFetch(всегоИгроков) {
  const ВЕРХУШКИ = 25;
  const ПОТОЛОК = 50;
  const все = [];
  for (let м = 1; м <= всегоИгроков; м++) все.push(игрок(м));

  return function (адрес, настройки) {
    const тело = JSON.parse((настройки && настройки.body) || '{}');
    if (тело.продолжение) {
      const начало = Number(тело.продолжение) || 0;
      const сколькоДать = Math.min(тело.сколько || 25, ПОТОЛОК);
      const строки = все.slice(начало, начало + сколькоДать);
      const конец = начало + строки.length;
      return Promise.resolve({
        json: function () {
          return Promise.resolve({
            ок: true,
            всего: всегоИгроков,
            строки: строки,
            продолжение: конец < всегоИгроков ? String(конец) : null
          });
        }
      });
    }
    const верхушка = все.slice(0, Math.min(всегоИгроков, ВЕРХУШКИ));
    return Promise.resolve({
      json: function () {
        return Promise.resolve({
          ок: true,
          узналиВас: true,
          игра: тело.игра,
          всего: всегоИгроков,
          яВТаблице: false,
          я: null,
          верхушка: верхушка,
          вокругМеня: [],
          продолжение: верхушка.length < всегоИгроков ? String(верхушка.length) : null,
          сила: null,
          друзья: { естьДрузья: false, верхушка: [], вокругМеня: [], всего: 0 }
        });
      }
    });
  };
}

function строкиСписка(таблица) {
  return Array.prototype.slice.call(таблица.querySelectorAll('.рейтинг-строка')).filter(function (с) {
    return !с.classList.contains('рейтинг-строка--шапка') && !с.classList.contains('рейтинг-строка--разрыв');
  });
}

/* Ждём, пока список перестанет меняться: пока идут автодогрузки, число
   строк растёт по кусочкам, курсор рано или поздно кончается (или
   набирается предел в 100). Три одинаковых замера подряд — список
   остановился сам. */
async function дождатьсяСтабильности(документ, максПопыток) {
  let предыдущее = -1;
  let стабильноПодряд = 0;
  for (let i = 0; i < (максПопыток || 80); i++) {
    await ждать(15);
    const таблица = документ.getElementById('рейтинг-таблица');
    const текущее = таблица ? строкиСписка(таблица).length : 0;
    if (текущее === предыдущее) {
      стабильноПодряд += 1;
      if (стабильноПодряд >= 3) return текущее;
    } else {
      стабильноПодряд = 0;
    }
    предыдущее = текущее;
  }
  return предыдущее;
}

async function сценарий(имя, всегоИгроков, ожидаемыйПодиум, ожидаемыхСтрок) {
  const поднятый = бр.поднять(исходникРабочий, {
    имяФайла: 'js/рейтинг-экран.js',
    fetch: сделатьFetch(всегоИгроков)
  });
  поднятый.окно.ЭкранРейтинга.открыть('все');
  await дождатьсяСтабильности(поднятый.документ);

  const таблица = поднятый.документ.getElementById('рейтинг-таблица');
  проверить(имя + ': таблица найдена', Boolean(таблица));
  if (!таблица) return;

  const подиум = таблица.querySelectorAll('.рейтинг-подиум-карточка');
  проверить(имя + ': на подиуме ровно ' + ожидаемыйПодиум + ' карточки', подиум.length === ожидаемыйПодиум,
    'нашлось: ' + подиум.length);

  const строки = строкиСписка(таблица);
  проверить(имя + ': под подиумом ровно ' + ожидаемыхСтрок + ' строк', строки.length === ожидаемыхСтрок,
    'нашлось: ' + строки.length);

  const итог = таблица.querySelector('.рейтинг-список-конец__итог');
  const текстИтога = итог ? итог.textContent : '';
  проверить(имя + ': подписи «Все игроки показаны» нет', текстИтога.indexOf('Все игроки показаны') === -1,
    'текст: «' + текстИтога + '»');
  проверить(имя + ': подписи «Показаны первые» нет', текстИтога.indexOf('Показаны первые') === -1,
    'текст: «' + текстИтога + '»');

  const кнопкаЕщё = поднятый.документ.getElementById('кнопка-рейтинг-показать-ещё');
  проверить(имя + ': кнопки «Показать ещё» нет', !кнопкаЕщё);

  проверить(имя + ': ошибок в консоли нет', поднятый.ошибкиКонсоли.length === 0,
    поднятый.ошибкиКонсоли.join('; '));
}

(async function () {
  await сценарий('150 игроков', 150, 3, 97);
  await сценарий('5 игроков', 5, 3, 2);

  console.log('');
  console.log('Итого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
  process.exitCode = провалов ? 1 : 0;
})();
