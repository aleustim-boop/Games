  проверить(селиКЗине.length === 1, 'г: за стол Зины посажен ровно один из двоих');
  проверить(людей(столЗины) === 2, 'г: за столом Зины ровно хозяйка и один гость');
  const второй = разом.find(function (о) { return о.тело.код !== столЗины.код; });
  проверить(Boolean(второй) && второй.тело.статус === 'ждёт', 'г: второй искатель ждёт в очереди');
