    проверить(галя.тело.статус === 'ждёт', 'б: за закрытый стол не сажают — Галя ждёт в очереди');
    console.log('и) Ответ «ждёт» без кода стола');
    проверить(галя.тело.код === undefined && галя.тело.пропуск === undefined &&
      галя.текст.indexOf(столВити.код) === -1,
      'и: в ответе «ждёт» нет ни кода, ни пропуска, ни кода чужого стола');
