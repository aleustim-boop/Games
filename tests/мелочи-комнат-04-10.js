/** Скопировать server/ и js/ во временную папку и вставить поломку. */
function приготовитьКопию(родитель, номер) {
  const поломка = ПОЛОМКИ[номер];
  if (!поломка) выйтиНеВставив('нет поломки №' + номер + ', номера: ' + Object.keys(ПОЛОМКИ).join(', '));
  const папка = fs.mkdtempSync(path.join(родитель, 'мелочи-' + номер + '-'));
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(папка, 'server'), {
    recursive: true,
    filter: function (откуда) {
      const имя = path.basename(откуда);
      return имя !== 'данные' && имя !== 'node_modules';
    }
  });
  require('./пути-проекта.js').скопироватьКод(КОРЕНЬ, папка, 'js');
  const куда = path.join(папка, поломка.файл);
  const текст = fs.readFileSync(куда, 'utf8');
  const нашлось = сколькоРаз(текст, поломка.было);
  if (нашлось !== 1) {
    выйтиНеВставив('поломку №' + номер + ' не вставить: текст «' + поломка.было + '» найден в ' +
                   поломка.файл + ' ' + нашлось + ' раз вместо одного. Проверка устарела — чините её.');
  }
  fs.writeFileSync(куда, текст.split(какВФайле(текст, поломка.было)).join(какВФайле(текст, поломка.стало)));
  console.log('ЛОМАЮЩИЙ ЗАПУСК №' + номер + ': ' + поломка.что);
  return папка;
}

/** Один дочерний запуск с поломкой. */
function запуститьПоломку(родитель, номер) {
  return new Promise(function (готово) {
    const ребёнок = spawn(process.execPath, [__filename, '--сломать', родитель, String(номер)], { stdio: ['ignore', 'pipe', 'pipe'] });
    let вывод = '';
    ребёнок.stdout.on('data', function (к) { вывод += к; });
    ребёнок.stderr.on('data', function (к) { вывод += к; });
    ребёнок.on('close', function (код) {
      const итог = вывод.match(/Итого проверок: (\d+), провалов: (\d+)/);
      готово({ номер: номер, код: код, итог: итог, вывод: вывод });
    });
  });
}

/** Все поломки по очереди (по нескольку разом): каждая обязана покраснеть. */
