'use strict';

/* =====================================================================
   ДЕЛИТСЯ ЛИ ОСТАТОК КОЛОДЫ ПОРОВНУ.

   Откуда взялась эта проверка. Живой игрок написал: «у меня 2 карты
   и у соперника 2, а в колоде 4 — нужно поделить по 2, а не отдать мне
   все четыре». По общим правилам дурака игра была права: добор идёт
   по очереди, и первый набирает себе до шести. Но правила здесь —
   владельца, и он попросил делить поровну.

   Эта проверка меряет то, на что он жаловался, — числом:

     • сколько раз за партии колоды не хватило на всех, кому нужен добор;
     • в скольких из них ОДИН забрал весь остаток;
     • в скольких кто-то не получил из колоды НИ ОДНОЙ карты.

   Числа, которые дала она же до правки (600 партий вдвоём, обычный бот):
   213 случаев, «один забрал всё» — 83%, «остался без карт» — 65%.
   После правки: 212 случаев, 19% и 2%. Оставшиеся проценты неизбежны:
   одну карту на двоих нуждающихся поровну не делят.

   Поэтому проверка не требует нулей, а держит ПОТОЛКИ — они записаны
   ниже и с запасом отстоят от замеренного. Если однажды добор снова
   станет «всё первому», числа улетят к прежним 83% и 65%, и проверка
   покраснеет.

   Запуск:
       node tests/делится-ли-колода-поровну.js
       node tests/делится-ли-колода-поровну.js 600 2

   Первое число — сколько партий сыграть, второе — сколько игроков
   за столом (2…6).
   ===================================================================== */

const path = require('path');
const игра = require(path.join(__dirname, '..', 'js', 'game.js'));

const ПАРТИЙ = Number(process.argv[2] || 600);
const ИГРОКОВ = Number(process.argv[3] || 2);

/* Потолки. Замер после правки дал 19% и 2%; берём с запасом, чтобы
   проверка не краснела от случайной раздачи, но ловила возврат
   к прежнему порядку (там было 83% и 65%). */
const ПОТОЛОК_ЗАБРАЛ_ВСЁ = 35;      // процентов
const ПОТОЛОК_ОСТАЛСЯ_НИ_С_ЧЕМ = 12;

/** Сколько карт не хватает игроку до полной руки. */
function нехватка(партия, игрок) {
  return Math.max(0, игра.КАРТ_В_РУКЕ - партия.руки[игрок].length);
}

function замер() {
  let случаев = 0, забралВсё = 0, осталсяНиСЧем = 0;
  const примеры = [];

  for (let номер = 0; номер < ПАРТИЙ; номер++) {
    const партия = игра.создатьПартию({
      сложность: 'обычный', игроков: ИГРОКОВ, зерно: 700000 + номер
    });
    let шагов = 0;
    while (!партия.завершена && шагов++ < 4000) {
      const колодаДо = партия.колода.length;
      const рукиДо = {};
      const нужноБыло = {};
      for (const игрок of партия.игроки) {
        рукиДо[игрок] = партия.руки[игрок].length;
        нужноБыло[игрок] = нехватка(партия, игрок);
      }

      игра.ходБота(партия, игра.ктоХодит(партия), 'обычный');

      /* Ловим ровно тот случай, ради которого всё: колода опустела этим
         ходом, а нуждавшихся было несколько, и на всех не хватило. */
      if (колодаДо === 0 || партия.колода.length > 0) continue;
      let надоБыло = 0, нуждались = 0;
      for (const игрок of партия.игроки) {
        надоБыло += нужноБыло[игрок];
        if (нужноБыло[игрок] > 0) нуждались++;
      }
      if (нуждались < 2 || колодаДо >= надоБыло) continue;

      случаев++;
      let больше_всех = 0, безКарт = 0;
      const взяли = [];
      for (const игрок of партия.игроки) {
        /* Считаем только карты ИЗ КОЛОДЫ: прирост руки нам не годится,
           потому что игрок мог в этом же ходу забрать карты со стола.
           Верхняя граница проста — сколько ему не хватало. */
        const взял = Math.min(нужноБыло[игрок],
                              Math.max(0, партия.руки[игрок].length - рукиДо[игрок]));
        взяли.push(взял);
        if (взял > больше_всех) больше_всех = взял;
        if (взял === 0 && нужноБыло[игрок] > 0) безКарт++;
      }
      if (больше_всех === колодаДо) забралВсё++;
      if (безКарт > 0) осталсяНиСЧем++;
      if (примеры.length < 5) {
        примеры.push('в колоде было ' + колодаДо + ', не хватало ' +
                     партия.игроки.map(function (и) { return нужноБыло[и]; }).join(' и ') +
                     ' → взяли ' + взяли.join(' и '));
      }
    }
  }
  return { случаев: случаев, забралВсё: забралВсё, осталсяНиСЧем: осталсяНиСЧем, примеры: примеры };
}

function доля(часть, всего) {
  return всего > 0 ? Math.round(часть * 100 / всего) : 0;
}

const итог = замер();
console.log('партий: ' + ПАРТИЙ + ', игроков за столом: ' + ИГРОКОВ);
console.log('случаев «колоды на всех не хватило»: ' + итог.случаев);

if (итог.случаев === 0) {
  console.log('');
  console.log('ПРОВАЛ: ни одного случая не встретилось — проверка ничего не мерила.');
  console.log('Так бывает, если партий слишком мало или добор перестал работать вовсе.');
  process.exit(1);
}

const процентВсё = доля(итог.забралВсё, итог.случаев);
const процентНоль = доля(итог.осталсяНиСЧем, итог.случаев);
console.log('   один забрал весь остаток: ' + итог.забралВсё + ' (' + процентВсё + '%), потолок ' + ПОТОЛОК_ЗАБРАЛ_ВСЁ + '%');
console.log('   кто-то не получил ни одной: ' + итог.осталсяНиСЧем + ' (' + процентНоль + '%), потолок ' + ПОТОЛОК_ОСТАЛСЯ_НИ_С_ЧЕМ + '%');
for (const пример of итог.примеры) console.log('   пример: ' + пример);

const беды = [];
if (процентВсё > ПОТОЛОК_ЗАБРАЛ_ВСЁ) {
  беды.push('один игрок забирает весь остаток слишком часто: ' + процентВсё + '% при потолке ' + ПОТОЛОК_ЗАБРАЛ_ВСЁ + '%');
}
if (процентНоль > ПОТОЛОК_ОСТАЛСЯ_НИ_С_ЧЕМ) {
  беды.push('слишком часто кто-то остаётся без карт: ' + процентНоль + '% при потолке ' + ПОТОЛОК_ОСТАЛСЯ_НИ_С_ЧЕМ + '%');
}

console.log('');
if (беды.length === 0) {
  console.log('ИТОГ: остаток колоды делится поровну.');
  process.exit(0);
}
console.log('ИТОГ: похоже, добор снова отдаёт всё первому.');
for (const беда of беды) console.log('  — ' + беда);
process.exit(1);
