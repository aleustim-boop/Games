const спать = (мс) => new Promise((ф) => setTimeout(ф, мс));

/** Копирует файлы и ломает их копии для проверки защит. Возвращает путь к временной папке. */
function подготовитьВременнуюПапку() {
  const tmp = path.join(os.tmpdir(), 'шахматы-проверка-защит-' + Date.now());
  fs.mkdirSync(tmp, { recursive: true });

  // Копируем структуру папок
  fs.mkdirSync(path.join(tmp, 'js'), { recursive: true });

  // Копируем шахматы.html
  const шахматыИсходный = path.join(__dirname, '..', 'шахматы.html');
  const шахматыКопия = path.join(tmp, 'шахматы.html');
  fs.copyFileSync(шахматыИсходный, шахматыКопия);

  // Копируем js/шахматы-экран.js и все необходимые js файлы
  const jsПапка = path.join(__dirname, '..', 'js');
  const jsФайлы = fs.readdirSync(jsПапка).filter(f => f.endsWith('.js'));
  for (const файл of jsФайлы) {
    fs.copyFileSync(
      path.join(jsПапка, файл),
      path.join(tmp, 'js', файл)
    );
  }

  // Копируем style.css
  const styleCss = path.join(__dirname, '..', 'style.css');
  fs.copyFileSync(styleCss, path.join(tmp, 'style.css'));

  return tmp;
}

/** Ломает три защиты в копиях файлов. Проверяет, что замены произошли. */
function ломатьТриЗащиты(tmp) {
  const результаты = [];

  // ЗАЩИТА 1: класс поле--тёмное в js/шахматы-экран.js
  {
    const файл = path.join(tmp, 'js', 'шахматы-экран.js');
    let содержимое = fs.readFileSync(файл, 'utf-8');
    const было = содержимое;
    // Ломаем: заменяем 'поле--тёмное' на 'поле--тёмное-СЛОМАНО'
    содержимое = содержимое.replace(/('поле--тёмное'|"поле--тёмное")/g, "'поле--тёмное-СЛОМАНО'");

    if (было === содержимое) {
      результаты.push({ защита: 'поле--тёмное', успех: false, ошибка: 'не найдено в файле' });
    } else {
      fs.writeFileSync(файл, содержимое, 'utf-8');
      результаты.push({ защита: 'поле--тёмное', успех: true });
    }
  }

  // ЗАЩИТА 2: класс лист-ещё__строка в шахматы.html
  {
    const файл = path.join(tmp, 'шахматы.html');
    let содержимое = fs.readFileSync(файл, 'utf-8');
    const было = содержимое;
    // Ломаем: заменяем class="лист-ещё__строка" на class="лист-ещё__строка-СЛОМАНО"
    содержимое = содержимое.replace(/class="лист-ещё__строка"/g, 'class="лист-ещё__строка-СЛОМАНО"');
    содержимое = содержимое.replace(/class='лист-ещё__строка'/g, "class='лист-ещё__строка-СЛОМАНО'");

    if (было === содержимое) {
      результаты.push({ защита: 'лист-ещё__строка', успех: false, ошибка: 'не найдено в файле' });
    } else {
      fs.writeFileSync(файл, содержимое, 'utf-8');
      результаты.push({ защита: 'лист-ещё__строка', успех: true });
    }
  }

  // ЗАЩИТА 3: <button> под #экран-шахмат в шахматы.html
  {
    const файл = path.join(tmp, 'шахматы.html');
    let содержимое = fs.readFileSync(файл, 'utf-8');
    const было = содержимое;

    // Найти #экран-шахмат и все <button> внутри него до следующего </section>
    // Используем простую замену: <button id="... до </section id="экран-шахмат"
    const начало = содержимое.indexOf('id="экран-шахмат"');
    if (начало === -1) {
      результаты.push({ защита: 'button-тег', успех: false, ошибка: 'не найден элемент #экран-шахмат' });
    } else {
      const конец = содержимое.indexOf('</section>', начало);
      if (конец === -1) {
        результаты.push({ защита: 'button-тег', успех: false, ошибка: 'не найден закрывающий </section>' });
      } else {
        const часть = содержимое.substring(начало, конец);
        const новаяЧасть = часть.replace(/<button(\s[^>]*)>/g, '<div$1>');
        if (часть === новаяЧасть) {
          результаты.push({ защита: 'button-тег', успех: false, ошибка: 'не найдены <button> внутри экрана' });
        } else {
          содержимое = содержимое.substring(0, начало) + новаяЧасть + содержимое.substring(конец);
          fs.writeFileSync(файл, содержимое, 'utf-8');
          результаты.push({ защита: 'button-тег', успех: true });
        }
      }
    }
  }

  return результаты;
}

/** Поднимает локальный сервер в отдельном процессе для временной папки. */
function поднятьСервер(tmp, порт) {
  const сервер = spawn('node', [
    path.join(__dirname, 'локальный-сервер.js'),
    String(порт)
  ], {
    env: Object.assign({}, process.env, { КОРЕНЬ_СЕРВЕРА: tmp }),
    stdio: 'pipe'
  });

  return new Promise((resolve, reject) => {
    let выход = '';
    let ошибка = '';

    const таймаут = setTimeout(() => {
      reject(new Error('Сервер не поднялся за 5 секунд'));
    }, 5000);

    сервер.stdout.on('data', (данные) => {
      выход += данные.toString();
      console.log('  сервер: ' + данные.toString().trim());
      if (выход.includes('запущен')) {
        clearTimeout(таймаут);
        resolve(сервер);
      }
    });

    сервер.stderr.on('data', (данные) => {
      ошибка += данные.toString();
      console.log('  ошибка сервера: ' + данные.toString().trim());
    });

    сервер.on('error', (е) => {
      clearTimeout(таймаут);
      reject(е);
    });
  });
}

/** Открывает страницу по произвольному адресу для тестирования. */
async function открытьСтраницу(браузер, ш, в, адрес) {
  const окно = await браузер.newContext({ viewport: { width: ш, height: в }, hasTouch: true, deviceScaleFactor: 2 });
  const страница = await окно.newPage();
  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
    красные.push('консоль: ' + м.text());
  });

  await подготовитьПодделку(страница, { версия: '8.0', полныйЭкран: 'дают' });

  await страница.goto(адрес);
  await спать(700);

  await страница.evaluate(() => {
    document.documentElement.classList.remove('в-телеграме');
  });

  return { окно, страница, красные };
}

/** Проверяет три защиты в браузере. Ожидает, что файлы уже испорчены. */
async function проверитьЗащиты(браузер, адрес) {
  console.log('\n=== ПРОВЕРКА ТРЁХ ЗАЩИТ ===');

  // Проверка 1: поле--тёмное
  console.log('\n--- Защита 1: поле--тёмное ---');
  {
    const { окно, страница, красные } = await открытьСтраницу(браузер, 390, 844, адрес);
    await страница.click('#лобби-вдвоём');
    await спать(700);

    const подсветка = await страница.evaluate(() => {
      const своиФигуры = [...document.querySelectorAll('#доска .фигура.фигура--белая')];
      if (!своиФигуры.length) return null;
      const клетка = (ф) => ф.closest('[class*="поле"]') || ф.parentElement;
      const тёмная = своиФигуры.find((ф) => клетка(ф).classList.contains('поле--тёмное'));
      const посмотреть = (ф) => {
        if (!ф) return null;
        const к = клетка(ф);
        ф.click();
        const выбрана = к.classList.contains('поле--выбрано');
        return { выбрана: выбрана };
      };
      if (тёмная) тёмная.click();
      const тёмнаяДанные = посмотреть(тёмная);
      return { тёмная: тёмнаяДанные };
    });

    if (подсветка && подсветка.тёмная) {
      проверить(подсветка.тёмная.выбрана, 'на тёмной клетке появился класс «поле--выбрано» (защита 1)');
    } else {
      проверить(false, 'поднять фигуру на тёмной клетке не вышло (защита 1)');
    }

    await окно.close();
  }

  // Проверка 2: лист-ещё__строка
  console.log('\n--- Защита 2: лист-ещё__строка ---');
  {
    const { окно, страница, красные } = await открытьСтраницу(браузер, 390, 844, адрес);
    await страница.click('#лобби-вдвоём');
    await спать(1000);

    let листОткрыт = false;
    try {
      await страница.waitForSelector('#кнопка-игра-ещё', { timeout: 5000 });
      await страница.click('#кнопка-игра-ещё');
      await спать(300);
      листОткрыт = true;
    } catch (е) {
      // Ошибка при открытии листа - это нормально, проверяем, есть ли строки класса
      console.log('  внимание: кнопка листа не появилась (это ожидаемо при ломаной защите)');
    }

    const вид = await страница.evaluate(() => {
      const строки = [...document.querySelectorAll('.лист-ещё__строка')]
        .filter((у) => у.offsetParent !== null);
      return { строкНайдено: строки.length };
    });

    проверить(вид.строкНайдено > 0, 'в листе «⋯» нашлись видимые строки, не ноль: ' + вид.строкНайдено + ' (защита 2)');

    await окно.close();
  }

  // Проверка 3: <button> под #экран-шахмат
  console.log('\n--- Защита 3: button-тег под экран-шахмат ---');
  {
    const { окно, страница, красные } = await открытьСтраницу(браузер, 320, 568, адрес);
    await страница.click('#лобби-вдвоём');
    await спать(700);

    const мера = await страница.evaluate(() => {
      const кнопки = [...document.querySelectorAll('#экран-шахмат button')].filter((к) => к.offsetParent !== null);
      return { кнопок: кнопки.length };
    });

    проверить(мера.кнопок > 0, 'под доской нашлись кнопки управления, не ноль: ' + мера.кнопок + ' (защита 3)');

    await окно.close();
  }
}

async function новая(браузер, ш, в, вТелеграме) {
  const окно = await браузер.newContext({ viewport: { width: ш, height: в }, hasTouch: true, deviceScaleFactor: 2 });
  const страница = await окно.newPage();
  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
    красные.push('консоль: ' + м.text());
  });

  await подготовитьПодделку(страница, { версия: '8.0', полныйЭкран: 'дают' });

  // Если в режиме Telegram, добавляем запоминание обработчика к SettingsButton и BackButton
  // (это делается ПОСЛЕ подготовитьПодделку, чтобы не переписать подделку)
  if (вТелеграме) {
    await страница.addInitScript(() => {
      // Оборачиваем существующие onClick и offClick в запоминание
      const обработчикиНастроек = {};
      const обработчикиСтрелки = {};

      if (window.Telegram && window.Telegram.WebApp) {
        // SettingsButton
        if (window.Telegram.WebApp.SettingsButton) {
          const оригинальнаяКнопка = window.Telegram.WebApp.SettingsButton;
          window.Telegram.WebApp.SettingsButton._запомненныеОбработчики = [];
          const оригинальныйOnClick = оригинальнаяКнопка.onClick;
          window.Telegram.WebApp.SettingsButton.onClick = function(обработчик) {
            window.Telegram.WebApp.SettingsButton._запомненныеОбработчики = [обработчик];
            if (typeof оригинальныйOnClick === 'function') return оригинальныйOnClick.call(this, обработчик);
          };
          window.Telegram.WebApp.SettingsButton._вызватьОбработчик = function() {
            const обработчики = window.Telegram.WebApp.SettingsButton._запомненныеОбработчики;
            if (обработчики && обработчики.length > 0 && typeof обработчики[0] === 'function') {
              обработчики[0]();
            }
          };
        }
      }
    });
  }

  await страница.goto(АДРЕС);
  await спать(700);

  // При ломающем запуске портим обе кнопки листа сразу при загрузке
  // (и на лобби, и на доске)
  if (СЛОМАТЬ) {
    await страница.evaluate(() => {
      const кнопкаЛобби = document.getElementById('кнопка-лобби-ещё');
      if (кнопкаЛобби) {
        кнопкаЛобби.id = 'кнопка-сломана-лобби';
      }
      const кнопкаДоска = document.getElementById('кнопка-игра-ещё');
      if (кнопкаДоска) {
        кнопкаДоска.id = 'кнопка-сломана-доска';
      }
    });
  }

  // Удаляем класс "в-телеграме", который подделка автоматически ставит, если не проверяем режим Telegram
  if (!вТелеграме) {
    await страница.evaluate(() => {
      document.documentElement.classList.remove('в-телеграме');
    });
  }
  return { окно, страница, красные };
}

