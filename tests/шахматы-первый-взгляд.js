/** Клик с коротким таймаутом, который никогда не бросает исключение —
    возвращает true/false. Без этого один переименованный id вешал весь
    прогон на встроенном таймауте Playwright (по умолчанию 30 секунд)
    и обрывал всё, что шло дальше по сценарию. */
async function клик(страница, селектор, таймаутМс) {
  try {
    await страница.click(селектор, { timeout: таймаутМс || 5000 });
    return true;
  } catch (е) {
    return false;
  }
}

