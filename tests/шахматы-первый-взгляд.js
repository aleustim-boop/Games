'use strict';

/* =====================================================================
   ШАХМАТЫ — ПЕРВЫЙ ВЗГЛЯД ГЛАЗАМИ.

   Игру проверяли поддельным браузером и числами: это ловит поведение,
   но не ловит вид. Ровно так мы получили нарды с шашками в две точки.
   Поэтому здесь — то, что решает глаз:

     1. ЗНАКИ ФИГУР: белая и чёрная фигура одного рода обязаны отличаться
        не только цветом строки в коде, а на экране. Меряем настоящий цвет
        и настоящий знак;
     2. доска и ДВА РЯДА КНОПОК на 320 точках;
     3. ряд из пяти образцов досок на экране «Оформление» — он новый;
     4. плашка превращения пешки: четыре крупные кнопки, их никто не жал.
        Пешку доводим до края по-настоящему, играя вдвоём;
     5. подсветка: видно ли, какую фигуру подняли и куда можно пойти —
        на светлой клетке и на тёмной (числа меряет оформитель, глаз — мы);
     6. партия против бота на каждом из трёх уровней: ходит ли он вообще.

   Запуск (страничный сервер уже поднят):
       node tests/шахматы-первый-взгляд.js 8080
   ===================================================================== */

const { chromium, подготовитьПодделку } = require('./браузер-робот.js');

const ПОРТ = Number(process.argv[2]) || 8080;
const АДРЕС = 'http://127.0.0.1:' + ПОРТ + '/шахматы.html';
const ПАПКА = 'tests/скриншоты/';

let провалов = 0;
function проверить(условие, слова) {
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}
const спать = (мс) => new Promise((ф) => setTimeout(ф, мс));

async function новая(браузер, ш, в) {
  const окно = await браузер.newContext({ viewport: { width: ш, height: в }, hasTouch: true, deviceScaleFactor: 2 });
  const страница = await окно.newPage();
  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
    красные.push('консоль: ' + м.text());
  });
  await подготовитьПодделку(страница, { версия: '8.0', полныйЭкран: 'дают' });
  await страница.goto(АДРЕС);
  await спать(700);
  return { окно, страница, красные };
}

(async () => {
  console.log('Шахматы — первый взгляд. Страница: ' + АДРЕС);
  const браузер = await chromium.launch();

  /* ================================================================
     1. Знаки фигур: отличимы ли белые от чёрных
     ================================================================ */
  console.log('\n=== Знаки фигур ===');
  const { окно, страница, красные } = await новая(браузер, 390, 844);
  await страница.click('#кнопка-вдвоём');
  await спать(700);

  const фигуры = await страница.evaluate(() => {
    const все = [...document.querySelectorAll('.фигура')];
    const разбор = все.map((ф) => {
      const с = getComputedStyle(ф);
      return {
        знак: (ф.textContent || '').trim(),
        белая: ф.classList.contains('фигура--белая'),
        цвет: с.color,
        размер: Math.round(ф.getBoundingClientRect().width) + '×' + Math.round(ф.getBoundingClientRect().height),
        шрифт: Math.round(parseFloat(с.fontSize))
      };
    });
    const белые = разбор.filter((ф) => ф.белая);
    const чёрные = разбор.filter((ф) => !ф.белая);
    return {
      всего: разбор.length,
      белых: белые.length, чёрных: чёрные.length,
      знакиБелых: [...new Set(белые.map((ф) => ф.знак))],
      знакиЧёрных: [...new Set(чёрные.map((ф) => ф.знак))],
      цветБелых: [...new Set(белые.map((ф) => ф.цвет))],
      цветЧёрных: [...new Set(чёрные.map((ф) => ф.цвет))],
      размер: разбор.length ? разбор[0].размер : '—',
      шрифт: разбор.length ? разбор[0].шрифт : 0
    };
  });
  console.log('  фигур ' + фигуры.всего + ' (белых ' + фигуры.белых + ', чёрных ' + фигуры.чёрных +
    '), размер ' + фигуры.размер + ', шрифт ' + фигуры.шрифт + ' точек');
  console.log('  знаки белых: ' + фигуры.знакиБелых.join(' ') );
  console.log('  знаки чёрных: ' + фигуры.знакиЧёрных.join(' '));
  console.log('  цвет белых: ' + фигуры.цветБелых.join(', ') + ' | цвет чёрных: ' + фигуры.цветЧёрных.join(', '));

  проверить(фигуры.всего === 32, 'на доске все 32 фигуры: ' + фигуры.всего);
  проверить(фигуры.шрифт >= 18, 'знак фигуры крупный: ' + фигуры.шрифт + ' точек');
  /* Главное: белую и чёрную нельзя перепутать. Отличие должно быть либо
     в самом знаке, либо в цвете — иначе играть нельзя. */
  const знакиРазные = фигуры.знакиБелых.join('') !== фигуры.знакиЧёрных.join('');
  const цветаРазные = фигуры.цветБелых.join('') !== фигуры.цветЧёрных.join('');
  проверить(знакиРазные || цветаРазные,
    'белые и чёрные фигуры отличимы' + (знакиРазные ? ' знаком' : '') + (цветаРазные ? ' цветом' : ''));
  await страница.screenshot({ path: ПАПКА + 'шахматы-фигуры-390.png' });
  console.log('  снимок: ' + ПАПКА + 'шахматы-фигуры-390.png');

  /* ================================================================
     2. Подсветка: что подняли и куда можно
     ================================================================ */
  console.log('\n=== Подсветка: видно ли поднятую фигуру и её ходы ===');
  const подсветка = await страница.evaluate(() => {
    /* Поднимаем пешку на СВЕТЛОЙ клетке и запоминаем, что изменилось. */
    const своиФигуры = [...document.querySelectorAll('.фигура--может-ходить, .фигура--белая')];
    if (!своиФигуры.length) return null;
    const клетка = (ф) => ф.closest('[class*="поле"]') || ф.parentElement;
    const светлая = своиФигуры.find((ф) => /светл|бел/i.test(клетка(ф).className));
    const тёмная = своиФигуры.find((ф) => /тёмн|чёрн/i.test(клетка(ф).className));
    const посмотреть = (ф) => {
      if (!ф) return null;
      const к = клетка(ф);
      const доНажатия = getComputedStyle(к);
      const было = { фон: доНажатия.backgroundColor, рамка: доНажатия.outlineColor + ' ' + доНажатия.outlineWidth,
        обвод: доНажатия.boxShadow.slice(0, 40) };
      ф.click();
      const после = getComputedStyle(к);
      const стало = { фон: после.backgroundColor, рамка: после.outlineColor + ' ' + после.outlineWidth,
        обвод: после.boxShadow.slice(0, 40) };
      const можно = [...document.querySelectorAll('.поле--можно')].map((п) => {
        const с = getComputedStyle(п);
        return { фон: с.backgroundColor, обвод: с.boxShadow.slice(0, 40), класс: п.className.slice(0, 40) };
      });
      return { клетка: к.className.slice(0, 40), было: было, стало: стало, помечено: можно.length, примеры: можно.slice(0, 2) };
    };
    const светлаяДанные = посмотреть(светлая);
    /* Снимаем выбор и пробуем тёмную. */
    if (светлая) светлая.click();
    const тёмнаяДанные = посмотреть(тёмная);
    return { светлая: светлаяДанные, тёмная: тёмнаяДанные };
  });
  if (подсветка && подсветка.светлая) {
    console.log('  светлая клетка (' + подсветка.светлая.клетка + '):');
    console.log('    было  ' + JSON.stringify(подсветка.светлая.было));
    console.log('    стало ' + JSON.stringify(подсветка.светлая.стало));
    console.log('    помечено ходов: ' + подсветка.светлая.помечено +
      (подсветка.светлая.примеры.length ? ', пример: ' + JSON.stringify(подсветка.светлая.примеры[0]) : ''));
    проверить(JSON.stringify(подсветка.светлая.было) !== JSON.stringify(подсветка.светлая.стало),
      'на светлой клетке видно, что фигуру подняли (вид клетки изменился)');
    проверить(подсветка.светлая.помечено > 0, 'куда можно пойти — помечено: ' + подсветка.светлая.помечено);
  } else {
    проверить(false, 'поднять фигуру на светлой клетке не вышло');
  }
  if (подсветка && подсветка.тёмная) {
    console.log('  тёмная клетка (' + подсветка.тёмная.клетка + '): было ' +
      JSON.stringify(подсветка.тёмная.было) + ' → стало ' + JSON.stringify(подсветка.тёмная.стало));
    проверить(JSON.stringify(подсветка.тёмная.было) !== JSON.stringify(подсветка.тёмная.стало),
      'на тёмной клетке видно, что фигуру подняли');
  }
  await страница.screenshot({ path: ПАПКА + 'шахматы-подсветка-390.png' });
  console.log('  снимок: ' + ПАПКА + 'шахматы-подсветка-390.png');

  /* ================================================================
     3. Превращение пешки — проверяется НЕ ЗДЕСЬ
     ================================================================
     Здесь стенд играл настоящую партию за обе стороны и надеялся, что
     пешка дойдёт до края: «за 120 ходов не вышло» — и проверка краснела,
     ничего не поймав. Плашку превращения целиком, со всеми четырьмя
     кнопками и на узком экране, проверяет отдельный стенд, где позиция
     задаётся правилами, а не выигрывается:
         node tests/шахматы-превращение-четыре-кнопки.js
     Второй, случайный, способ ту же плашку не сторожит, а только
     подбрасывает ложные тревоги. */
  проверить(красные.length === 0, ('консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : '')));
  await окно.close();

  /* ================================================================
     4. Экран «Оформление»: пять образцов досок
     ================================================================ */
  console.log('\n=== Оформление: ряд образцов ===');
  {
    const { окно: о2, страница: с2, красные: к2 } = await новая(браузер, 390, 844);
    await с2.click('#кнопка-вдвоём'); await спать(500);
    await с2.click('#кнопка-оформление'); await спать(700);
    const вид = await с2.evaluate(() => {
      const э = document.getElementById('экран-оформления');
      const образцы = [...э.querySelectorAll('button, [class*="образ"]')]
        .filter((у) => у.offsetParent !== null && у.getBoundingClientRect().width > 20);
      const внешние = образцы.filter((у) => !образцы.some((д) => д !== у && д.contains(у)));
      const края = внешние.map((у) => {
        const к = у.getBoundingClientRect();
        return { ш: Math.round(к.width), в: Math.round(к.height), лево: Math.round(к.left), верх: Math.round(к.top),
          что: (у.textContent || '').trim().slice(0, 16) };
      });
      const рядов = new Set(края.map((к) => к.верх)).size;
      return { видим: э.classList.contains('экран--виден'), всего: края.length, рядов: рядов, края: края,
        ширинаСтраницы: document.documentElement.scrollWidth, окно: window.innerWidth,
        вОкне: края.every((к) => к.лево >= -1 && к.лево + к.ш <= window.innerWidth + 1) };
    });
    console.log('  экран открыт: ' + вид.видим + ', образцов и кнопок: ' + вид.всего + ', рядов: ' + вид.рядов);
    вид.края.slice(0, 8).forEach((к) => console.log('     · ' + к.что + ' ' + к.ш + '×' + к.в));
    проверить(вид.видим, 'экран «Оформление» открывается кнопкой из ряда под доской');
    проверить(вид.всего >= 5, 'образцов досок не меньше пяти: ' + вид.всего);
    проверить(вид.вОкне && вид.ширинаСтраницы <= вид.окно + 1,
      'ряд образцов не выехал за экран: ширина страницы ' + вид.ширинаСтраницы + ' при ' + вид.окно);
    проверить(к2.length === 0, 'консоль чистая' + (к2.length ? ': ' + к2.join(' | ') : ''));
    await с2.screenshot({ path: ПАПКА + 'шахматы-оформление.png', fullPage: true });
    console.log('  снимок: ' + ПАПКА + 'шахматы-оформление.png');
    await о2.close();
  }

  /* ================================================================
     5. Узкий экран: доска и два ряда кнопок
     ================================================================ */
  console.log('\n=== 320×568: доска и два ряда кнопок ===');
  {
    const { окно: о3, страница: с3, красные: к3 } = await новая(браузер, 320, 568);
    await с3.click('#кнопка-вдвоём'); await спать(700);
    const мера = await с3.evaluate(() => {
      const д = document.getElementById('доска').getBoundingClientRect();
      const кнопки = [...document.querySelectorAll('#экран-шахмат button')].filter((к) => к.offsetParent !== null);
      const ряды = new Set(кнопки.map((к) => Math.round(к.getBoundingClientRect().top)));
      return {
        доска: Math.round(д.width) + '×' + Math.round(д.height),
        доскаВОкне: д.right <= window.innerWidth + 1 && д.bottom <= window.innerHeight + 1,
        кнопок: кнопки.length, рядов: ряды.size,
        всеВОкне: кнопки.every((к) => к.getBoundingClientRect().bottom <= window.innerHeight + 1),
        заКраем: кнопки.filter((к) => к.getBoundingClientRect().bottom > window.innerHeight + 1)
          .map((к) => к.textContent.trim().slice(0, 18)),
        страницаКрутится: document.documentElement.scrollHeight > window.innerHeight + 1,
        мелких: кнопки.filter((к) => к.getBoundingClientRect().height < 40).length,
        ширина: document.documentElement.scrollWidth, окно: window.innerWidth
      };
    });
    console.log('  доска ' + мера.доска + ', кнопок ' + мера.кнопок + ' в ' + мера.рядов + ' ряда(ов)');
    проверить(мера.доскаВОкне, 'доска целиком в окне');
    /* Кнопки под доской обязаны быть достижимы: либо все в окне, либо
       страница прокручивается. Ни того, ни другого — значит человек
       до них просто не доберётся. */
    проверить(мера.всеВОкне || мера.страницаКрутится,
      'все кнопки под доской достижимы' + (мера.заКраем.length
        ? ': за краем окна остались ' + мера.заКраем.length + ' («' + мера.заКраем.join('», «') +
          '»), а страница не прокручивается'
        : ''));
    проверить(мера.мелких === 0, 'кнопки не мельче 40 точек: мелких ' + мера.мелких);
    проверить(мера.ширина <= мера.окно + 1, 'страница не едет вбок');
    проверить(к3.length === 0, 'консоль чистая' + (к3.length ? ': ' + к3.join(' | ') : ''));
    await о3.close();
  }

  /* ================================================================
     6. Бот на трёх уровнях: ходит ли он вообще
     ================================================================ */
  console.log('\n=== Бот на трёх уровнях ===');
  for (const уровень of ['лёгкий', 'обычный', 'сложный']) {
    const { окно: о4, страница: с4, красные: к4 } = await новая(браузер, 390, 844);
    await с4.click('#уровень-' + уровень).catch(() => {});
    await спать(200);
    await с4.click('#кнопка-с-ботом');
    await спать(800);
    let моих = 0;
    let ходилБот = false;
    for (let i = 0; i < 60 && !ходилБот; i++) {
      const что = await с4.evaluate(() => {
        const можно = document.querySelectorAll('.поле--можно');
        if (можно.length) { можно[Math.floor(Math.random() * можно.length)].click(); return 'пошли'; }
        /* Пометка «может ходить» есть не всегда — берём и просто свои
           фигуры, как это делает палец: тапнул и посмотрел, что подсветилось.
           Без этого запаса стенд писал «моих ходов 0» и молчал о том,
           что игра-то работает. */
        const свои = document.querySelectorAll('.фигура--может-ходить');
        if (свои.length) { свои[Math.floor(Math.random() * свои.length)].click(); return 'подняли'; }
        const мои = document.querySelectorAll('.фигура--белая');
        if (мои.length) { мои[Math.floor(Math.random() * мои.length)].click(); return 'подняли'; }
        return 'нечего';
      });
      if (что === 'пошли') моих++;
      await спать(что === 'нечего' ? 250 : 200);
      /* Бот сходил, если ход снова наш, а фигур на доске стало меньше или
         строка хода сменилась дважды. Проще: ждём появления его пометки. */
      ходилБот = await с4.evaluate(() => {
        const строка = (document.getElementById('строка-хода') || {}).textContent || '';
        return /ваш ход/i.test(строка) && document.querySelectorAll('.фигура').length <= 32;
      }) && моих >= 2;
    }
    const итог = await с4.evaluate(() => ({
      строка: (document.getElementById('строка-хода') || {}).textContent || '',
      фигур: document.querySelectorAll('.фигура').length,
      конец: document.getElementById('экран-итога').classList.contains('экран--виден')
    }));
    console.log('  ' + уровень + ': моих ходов ' + моих + ', на доске фигур ' + итог.фигур +
      ', строка «' + итог.строка.trim().slice(0, 40) + '»' + (итог.конец ? ', партия окончена' : ''));
    проверить(моих >= 2, уровень + ': ходить пальцем получается (ходов ' + моих + ')');
    проверить(итог.фигур <= 32 && итог.фигур >= 20, уровень + ': доска жива, фигур ' + итог.фигур);
    проверить(к4.length === 0, уровень + ': консоль чистая' + (к4.length ? ': ' + к4.join(' | ') : ''));
    await о4.close();
  }

  await браузер.close();
  console.log('\nИтог: провалов ' + провалов);
  process.exit(провалов ? 1 : 0);
})().catch((о) => { console.error('Стенд упал: ' + (о && о.stack || о)); process.exit(2); });
