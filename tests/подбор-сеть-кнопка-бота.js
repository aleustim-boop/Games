/* =====================================================================
   КНОПКА «ИГРАТЬ С БОТОМ» В БРАУЗЕРНОЙ СЕТИ — БЕЗ БРАУЗЕРА.

   Чисто node-проверка: браузер не запускается. js/сеть.js целиком грузится
   в песочницу (vm) с поддельным окружением (tests/поддельный-браузер.js)
   и поддельным fetch: каждый запрос к серверу запоминается, а ответом
   на него распоряжается сама проверка — когда и что ответить (или
   «сорвать связь»). Так можно воспроизвести гонки: запрос ещё летит, а игрок
   уже нажал «Отменить»; опрос принёс стол, а кнопка бота получила отказ.

   Что проверяем (ревью подбора «бота сажаем только по кнопке» нашло, что
   эти места в сеть.js не проверял никто):
     Раздел 1. Кнопка «с ботом», сервер отвечает 429 (и отдельно — молчит):
               Сеть.подобратьСБотом даёт { статус: 'ждём', причина }, а
               следующий опрос /подбор-новости уходит с ПРЕЖНИМ ключом.
     Раздел 2. Игрок отменил, пока запрос бота летел: клиент шлёт отмену
               по ключу очереди; а когда сервер всё-таки ответил комнатой
               с ботом — клиент шлёт выход по коду этой комнаты и за
               столом не остаётся.
     Раздел 3. Опрос принёс стол с человеком, а кнопке отказали (429):
               игрок садится именно за этот стол (код и пропуск из ответа
               опроса), выхода из него нет, второй комнаты не создаётся.
     Раздел 4. (наблюдение) кнопке отказали словом «из очереди убран», а
               опрос успел принести стол — что делает клиент; смотри вывод.

   Запуск:
       node tests/подбор-сеть-кнопка-бота.js
       node tests/подбор-сеть-кнопка-бота.js --сеть=<путь к копии сеть.js>

   Ломающие запуски (порча делается в КОПИИ js/сеть.js во временной папке
   ОС; настоящий файл не трогается; замена, не нашедшая строку ровно один
   раз, — провал запуска):
       node tests/подбор-сеть-кнопка-бота.js --сломать 1   (…до 5)
       node tests/подбор-сеть-кнопка-бота.js --сломать-все
   Порча 1 — после отказа бота ключ ожидания не возвращается (раздел 1).
   Порча 2 — отмена забывает ключ летящего запроса бота (раздел 2).
   Порча 3 — опрос не передаёт свой стол кнопке (раздел 3).
   Порча 4 — опоздавшая комната с ботом не покидается (раздел 2).
   Порча 5 — после отказа кнопки клиент не садится за стол опроса (раздел 3).

   Выход 0 — провалов нет, 1 — есть.
   ===================================================================== */

