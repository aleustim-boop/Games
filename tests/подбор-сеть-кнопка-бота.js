/* ---------------------------------------------------------------------
   Песочница: сеть.js + поддельный fetch, которым распоряжается проверка
   --------------------------------------------------------------------- */
function подождать() { return new Promise(function (г) { setTimeout(г, 0); }); }
async function тики(n) { for (let i = 0; i < (n || 6); i++) await подождать(); }

function создатьПесочницу(исходникСети) {
  const запросы = [];
  function подделанныйFetch(url, настройки) {
    const путь = decodeURIComponent(new URL(url).pathname);
    let тело = {};
    try { тело = JSON.parse((настройки && настройки.body) || '{}'); } catch (сбой) { тело = {}; }
    const з = { путь: путь, тело: тело };
    з.обещание = new Promise(function (ок, беда) {
      з.ответить = function (данные, номер) {
        const н = номер || 200;
        ок({ ok: н < 400, status: н, json: function () { return Promise.resolve(данные); } });
      };
      з.сорвать = function () { беда(new Error('сеть пропала')); };
    });
    запросы.push(з);
    return з.обещание;
  }
  const память = сделатьПамять(false);
  const рез = поднять(исходникСети, {
    документ: сделатьДокумент(),
    память: память,
    telegram: { initData: 'user=%7B%22id%22%3A1%2C%22first_name%22%3A%22Тест%22%7D&hash=abc' },
    fetch: подделанныйFetch,
    имяФайла: 'js/сеть.js'
  });
  const Сеть = рез.окно.Сеть;
  return {
    Сеть: Сеть,
    запросы: запросы,
    память: память,
    все: function (путь) { return запросы.filter(function (з) { return з.путь === путь; }); },
    /* Нужный запрос ОБЯЗАН найтись — иначе это провал, а не пропуск. */
    последний: function (путь) {
      const л = запросы.filter(function (з) { return з.путь === путь; });
      return л.length ? л[л.length - 1] : null;
    },
    /* Комната, за столом которой мы сейчас сидим, — из записи «вернуться в игру». */
    комнатаЗаСтолом: function () {
      for (const к of Object.keys(память.ящик)) {
        let о = null;
        try { о = JSON.parse(память.ящик[к]); } catch (сбой) { о = null; }
        if (о && typeof о === 'object' && о.код) return о;
      }
      return null;
    },
    /* Сколько запросов ушло по конкретной комнате (опрос стола и т. п.) */
    оКомнате: function (кодКомнаты) {
      return запросы.filter(function (з) { return з.тело && з.тело.код === кодКомнаты; });
    }
  };
}

/** Встали в очередь: сервер ответил «ждёт» с ключом. Вернуть песочницу. */
async function встатьВОчередь(исходникСети, ключ) {
  const п = создатьПесочницу(исходникСети);
  if (!п.Сеть || typeof п.Сеть.встатьВОчередь !== 'function' ||
      typeof п.Сеть.подобратьСБотом !== 'function' ||
      typeof п.Сеть.подождатьСоперника !== 'function' ||
      typeof п.Сеть.отменитьПодбор !== 'function') {
    throw new Error('в window.Сеть нет встатьВОчередь / подобратьСБотом / подождатьСоперника / отменитьПодбор');
  }
  const обещание = п.Сеть.встатьВОчередь();
  await тики();
  const з = п.последний('/подбор');
  if (!з) throw new Error('запрос «/подбор» не улетел (всего запросов: ' + п.запросы.length + ')');
  з.ответить({ статус: 'ждёт', ключОжидания: ключ });
  const итог = await обещание;
  if (!итог || итог.статус !== 'ждём') throw new Error('встать в очередь не вышло: ' + JSON.stringify(итог));
  return п;
}

/* ---------------------------------------------------------------------
   Раздел 1. Отказ бота (429 и молчание) — ключ ожидания остаётся прежним
   --------------------------------------------------------------------- */
async function раздел1Вариант(исходникСети, как) {
  const п = await встатьВОчередь(исходникСети, 'КЛЮЧ-1');
  const обещание = п.Сеть.подобратьСБотом();
  await тики();
  const зБота = п.последний('/подбор-с-ботом');
  проверить(Boolean(зБота), как + ': запрос «/подбор-с-ботом» улетел');
  if (!зБота) return;
  проверить(зБота.тело.ключОжидания === 'КЛЮЧ-1',
    как + ': кнопка бота несёт ключ очереди «КЛЮЧ-1» (получили ' + JSON.stringify(зБота.тело.ключОжидания) + ')');
  if (как.indexOf('429') !== -1) зБота.ответить({ ошибка: 'Слишком часто — подождите' }, 429);
  else зБота.сорвать();
  const итог = await обещание;
  проверить(итог && итог.статус === 'ждём',
    как + ': подобратьСБотом вернул статус «ждём» (получили ' + JSON.stringify(итог) + ')');
  проверить(Boolean(итог && typeof итог.причина === 'string' && итог.причина.length > 0),
    как + ': причина для показа не пустая (получили ' + JSON.stringify(итог && итог.причина) + ')');
  // Подбор остался в ожидании: следующий опрос уходит с ПРЕЖНИМ ключом.
  п.Сеть.подождатьСоперника();
  await тики();
  const опрос = п.последний('/подбор-новости');
  проверить(Boolean(опрос), как + ': после отказа опрос «/подбор-новости» снова уходит (а не «Подбор не запущен»)');
  проверить(Boolean(опрос) && опрос.тело.ключОжидания === 'КЛЮЧ-1',
    как + ': опрос уходит с прежним ключом «КЛЮЧ-1» (получили ' + JSON.stringify(опрос && опрос.тело.ключОжидания) + ')');
  проверить(п.все('/подбор').length === 1,
    как + ': второго «/подбор» (второй очереди) не было (было ' + п.все('/подбор').length + ')');
  проверить(п.все('/подбор-отмена').length === 0, как + ': отмену никто не слал');
}

