function исходникЭкрана(путь) { return fs.readFileSync(путь, 'utf8'); }

async function поднятьЭкран(исходник, ответБота) {
  const вызовы = { опрос: 0, отмена: 0, бот: 0, встать: 0 };
  const документ = сделатьДокумент();
  const рез = поднять(исходник, { документ: документ, имяФайла: 'js/подбор-экран.js' });
  рез.окно.Сеть = {
    встатьВОчередь: function () { вызовы.встать++; return Promise.resolve({ статус: 'ждём' }); },
    подождатьСоперника: function () { вызовы.опрос++; return new Promise(function () {}); },
    подобратьСБотом: function () { вызовы.бот++; return Promise.resolve(ответБота); },
    отменитьПодбор: function () { вызовы.отмена++; return Promise.resolve({ ок: true }); }
  };
  if (!рез.окно.ЭкранПодбора || typeof рез.окно.ЭкранПодбора.открыть !== 'function') {
    throw new Error('window.ЭкранПодбора.открыть не появилась');
  }
  рез.окно.ЭкранПодбора.открыть();
  await тики();
  return { вызовы: вызовы, документ: документ };
}

