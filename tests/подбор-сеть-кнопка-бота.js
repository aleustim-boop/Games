function заменитьРовноОдин(исходник, что, чем, описание) {
  let число = 0;
  if (typeof что === 'string') {
    число = исходник.split(что).length - 1;
  } else {
    const м = исходник.match(new RegExp(что.source, что.flags.indexOf('g') === -1 ? что.flags + 'g' : что.flags));
    число = м ? м.length : 0;
  }
  if (число !== 1) {
    throw new Error('порча «' + описание + '»: искомое нашлось ' + число + ' раз(а), а надо ровно один — приём устарел, поправь его');
  }
  return typeof что === 'string' ? исходник.split(что).join(чем) : исходник.replace(что, чем);
}

