function свободныйПорт() {
  return new Promise((готово, брак) => {
    const проба = http.createServer();
    проба.on('error', брак);
    проба.listen(0, АДРЕС_ХОЗЯИНА, () => {
      const порт = проба.address().port;
      проба.close(() => готово(порт));
    });
  });
}

async function выбратьСвободныйПорт(занятые) {
  for (let попытка = 0; попытка < 8; попытка++) {
    const порт = await свободныйПорт();
    if (ЗАПРЕЩЁННЫЕ_ПОРТЫ.indexOf(порт) === -1 && (занятые || []).indexOf(порт) === -1) return порт;
  }
  throw new Error('не удалось получить свободный порт, отличный от боевых 8790/8791 и уже занятых');
}

