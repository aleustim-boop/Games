async function замеритьПолоску(страница) {
  return страница.evaluate(() => {
    const экран = document.getElementById('экран-друга');
    if (!экран) return { найдено: false };
    const cs = getComputedStyle(экран, '::after');
    const rect = экран.getBoundingClientRect();
    const позиция = cs.position;
    const высота = parseFloat(cs.height) || 0;
    const bottomЧисло = parseFloat(cs.bottom);
    const bottom = isNaN(bottomЧисло) ? 0 : bottomЧисло;

    let предсказанныйНиз;
    if (позиция === 'fixed') {
      предсказанныйНиз = window.innerHeight - bottom;
    } else {
      // Старая беда (см. шапку файла): контейнер сам не двигается,
      // а абсолютный потомок в его контентных координатах стоит на
      // (rect.height - bottom) от верха контейнера при scrollTop=0,
      // и это место сдвигается на -scrollTop при прокрутке.
      предсказанныйНиз = (rect.height - bottom) - экран.scrollTop;
    }

    return {
      найдено: true,
      позиция: позиция,
      высота: высота,
      bottomСтрокой: cs.bottom,
      backgroundImage: cs.backgroundImage,
      scrollTop: экран.scrollTop,
      scrollHeight: экран.scrollHeight,
      clientHeight: экран.clientHeight,
      innerHeight: window.innerHeight,
      rectTop: rect.top,
      rectBottom: rect.bottom,
      предсказанныйНиз: предсказанныйНиз
    };
  });
}

/* ---------------------------------------------------------------------
   Честный пиксельный замер — без библиотек (в проекте нет node_modules).
   Снимок уже лежит в буфере (страница.screenshot() без path — Buffer),
   его же передаём В САМУ страницу строкой data:image/png;base64,…,
   рисуем на «<canvas>» и читаем «getImageData» — то же самое, что уже
   делает tests/снимок-рейтинг-золото.js для золотого кольца аватара.
   --------------------------------------------------------------------- */

async function прочитатьЦветаИзСнимка(страница, base64, xТочки, yТочки) {
  return страница.evaluate(async (аргументы) => {
    const { base64, xТочки, yТочки } = аргументы;
    const картинка = new Image();
    await new Promise((готово, брак) => {
      картинка.onload = готово;
      картинка.onerror = брак;
      картинка.src = 'data:image/png;base64,' + base64;
    });
    const холст = document.createElement('canvas');
    холст.width = картинка.width;
    холст.height = картинка.height;
    const кисть = холст.getContext('2d', { willReadFrequently: true });
    кисть.drawImage(картинка, 0, 0);

    function точка(x, y) {
      const xx = Math.min(холст.width - 1, Math.max(0, Math.round(x)));
      const yy = Math.min(холст.height - 1, Math.max(0, Math.round(y)));
      const d = кисть.getImageData(xx, yy, 1, 1).data;
      return [d[0], d[1], d[2]];
    }
    function средний(y) {
      const цвета = xТочки.map((x) => точка(x, y));
      const сумма = [0, 0, 0];
      цвета.forEach((c) => { сумма[0] += c[0]; сумма[1] += c[1]; сумма[2] += c[2]; });
      return [сумма[0] / цвета.length, сумма[1] / цвета.length, сумма[2] / цвета.length];
    }

    const итог = {};
    Object.keys(yТочки).forEach((имя) => { итог[имя] = средний(yТочки[имя]); });
    return итог;
  }, { base64: base64, xТочки: xТочки, yТочки: yТочки });
}

function разницаЦвета(a, b) {
  return Math.abs(a[0] - b[0]) + Math.abs(a[1] - b[1]) + Math.abs(a[2] - b[2]);
}

function строкаЦвета(c) {
  return 'rgb(' + Math.round(c[0]) + ',' + Math.round(c[1]) + ',' + Math.round(c[2]) + ')';
}

