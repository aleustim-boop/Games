    const началоОтКрытой = позицияСелектора + МАРКЕР_СЕЛЕКТОРА.length - 1; // позиция {
    const хвостОтКрытой = оригинал.slice(началоОтКрытой + 1);
    const позицияЗакрытойОтн = хвостОтКрытой.indexOf('}');
    if (позицияЗакрытойОтн === -1) {
      console.log('ОШИБКА: в style.css не нашлась закрывающая скобка после селектора полоски — файл повреждён.');
      process.exit(1);
    }

    // Экстрактируем содержимое правила (между { и })
    const началоСодержимого = началоОтКрытой + 1;
    const конецСодержимого = началоОтКрытой + 1 + позицияЗакрытойОтн;
