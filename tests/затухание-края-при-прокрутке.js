async function прогнать(подменаStyleCss, метка) {
  const строки = [];
  const проваленныеИмена = [];
  let провалов = 0;
  function проверить(имя, условие, детали) {
    строки.push((условие ? '  ок    — ' : '  ПЛОХО — ') + имя + (детали ? ' (' + детали + ')' : ''));
    if (!условие) { провалов++; проваленныеИмена.push(имя); }
  }

  const порты = [];
  const портСтраниц = await выбратьСвободныйПорт(порты); порты.push(портСтраниц);
  const портБеды = await выбратьСвободныйПорт(порты); порты.push(портБеды); // сознательно никто не слушает

  console.log('  [' + метка + '] порт страниц: ' + портСтраниц + ', порт беды (сервер комнат, пустой): ' + портБеды +
    ' (' + (подменаStyleCss !== null ? 'style.css подменён испорченной копией из temp' : 'style.css родной, с диска проекта') + ')');

  const сервер = await поднятьСервер(портСтраниц, подменаStyleCss);
  let браузер = null;
  const снимки = [];

  try {
    браузер = await chromium.launch();
    const контекст = await браузер.newContext({ viewport: { width: ШИРИНА, height: ВЫСОТА }, hasTouch: true });
    const страница = await контекст.newPage();

    const красные = [];
    страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
    страница.on('console', (м) => {
      if (м.type() !== 'error') return;
      const текст = м.text();
      const л = м.location && м.location();
      const откуда = (л && л.url) || '';
      const вместе = текст + ' ' + откуда;
      // Ожидаемый шум: наша же подделка Telegram (route.abort на настоящий
      // скрипт) и сетевые отказы к заведомо мёртвому порту сервера комнат —
      // это и есть проверяемый сценарий «сервер недоступен», не поломка игры.
      if (/telegram-web-app\.js|telegram\.org/.test(вместе)) return;
      if (/ERR_CONNECTION_REFUSED|ERR_FAILED|net::/i.test(текст)) return;
      красные.push('консоль: ' + текст + (откуда ? ' (' + откуда + ')' : ''));
    });

    await подготовитьПодделку(страница, { версия: '7.10' });

    const адрес = 'http://' + АДРЕС_ХОЗЯИНА + ':' + портСтраниц + '/index.html?сервер=' +
      encodeURIComponent('http://' + АДРЕС_ХОЗЯИНА + ':' + портБеды);
    console.log('  [' + метка + '] открываю: ' + адрес);
    await страница.goto(адрес, { waitUntil: 'domcontentloaded' });

    const другВиден = await дойтиДоЭкранаДругаСБедой(страница);
    проверить('дошли до экрана «Игра с другом» с бедой (#экран-друга)', другВиден === true);

    if (!другВиден) {
      проверить('прокрутка есть (scrollHeight > clientHeight)', false, 'экран не появился — замерить нечего');
      проверить('плашка беды #нет-сервера-главное нашлась', false, 'экран не появился');
      проверить('полоска-затухание ДО прокрутки: ненулевая высота, низ у края видимой области (±2px)', false, 'экран не появился');
      проверить('полоска-затухание ПОСЛЕ прокрутки: по-прежнему у края видимой области (±2px)', false, 'экран не появился');
    } else {
      await спать(400);

      /* ---------------- Пункт 2: плашка беды — замер, не провал ---------------- */
      const плашка = await страница.evaluate(() => {
        const эл = document.getElementById('нет-сервера-главное');
        if (!эл) return null;
        const r = эл.getBoundingClientRect();
        return { top: r.top, bottom: r.bottom, height: r.height };
      });
      проверить('плашка беды #нет-сервера-главное нашлась', плашка !== null);
      if (плашка) {
        const непоказано = плашка.bottom - ВЫСОТА;
        console.log('  [' + метка + '] плашка беды: top=' + плашка.top.toFixed(1) + ' bottom=' + плашка.bottom.toFixed(1) +
          ' — при видимой высоте ' + ВЫСОТА + ' не видно снизу ' + непоказано.toFixed(1) + 'px (замер, не провал)');
      }

      /* ---------------- Пункт 1: прокрутка есть ---------------- */
      const доПрокрутки = await замеритьПолоску(страница);
      проверить('узел #экран-друга нашёлся при замере полоски', доПрокрутки.найдено === true);
      if (доПрокрутки.найдено) {
        проверить('на экране есть прокрутка (scrollHeight > clientHeight)',
          доПрокрутки.scrollHeight > доПрокрутки.clientHeight,
          'scrollHeight=' + доПрокрутки.scrollHeight + ', clientHeight=' + доПрокрутки.clientHeight);

        console.log('  [' + метка + '] ДО прокрутки: position=' + доПрокрутки.позиция + ', height=' + доПрокрутки.высота +
          'px, bottom=' + доПрокрутки.bottomСтрокой + ', scrollTop=' + доПрокрутки.scrollTop +
          ', предсказанный низ полоски=' + доПрокрутки.предсказанныйНиз.toFixed(1) + ' (видимая область=' + доПрокрутки.innerHeight + ')');

        if (!fs.existsSync(ПАПКА_СНИМКОВ)) fs.mkdirSync(ПАПКА_СНИМКОВ, { recursive: true });
        const файлДо = path.join(ПАПКА_СНИМКОВ, 'затухание-до-прокрутки-390x844' + (метка === 'сломано' ? '-сломано' : '') + '.png');
        await страница.screenshot({ path: файлДо });
        снимки.push(файлДо);
        console.log('  [' + метка + '] снимок ДО прокрутки: ' + файлДо);
        проверить('снимок ДО прокрутки сохранён на диск', fs.existsSync(файлДо));

        const разницаДо = Math.abs(доПрокрутки.предсказанныйНиз - доПрокрутки.innerHeight);
        проверить('полоска-затухание ДО прокрутки: ненулевая высота, низ у края видимой области (±2px)',
          доПрокрутки.высота > 0 && разницаДо <= 2,
          'высота=' + доПрокрутки.высота + 'px, |предсказанный низ − видимая область|=' + разницаДо.toFixed(1) + 'px');

        /* ---------------- Прокрутка донизу ---------------- */
        await страница.evaluate(() => {
          const экран = document.getElementById('экран-друга');
          if (экран) экран.scrollTop = экран.scrollHeight;
        });
        await спать(300);

        const послеПрокрутки = await замеритьПолоску(страница);
        console.log('  [' + метка + '] ПОСЛЕ прокрутки: position=' + послеПрокрутки.позиция + ', height=' + послеПрокрутки.высота +
          'px, bottom=' + послеПрокрутки.bottomСтрокой + ', scrollTop=' + послеПрокрутки.scrollTop +
          ', предсказанный низ полоски=' + послеПрокрутки.предсказанныйНиз.toFixed(1) + ' (видимая область=' + послеПрокрутки.innerHeight + ')');

        const файлПосле = path.join(ПАПКА_СНИМКОВ, 'затухание-после-прокрутки-390x844' + (метка === 'сломано' ? '-сломано' : '') + '.png');
        await страница.screenshot({ path: файлПосле });
        снимки.push(файлПосле);
        console.log('  [' + метка + '] снимок ПОСЛЕ прокрутки: ' + файлПосле);
        проверить('снимок ПОСЛЕ прокрутки сохранён на диск', fs.existsSync(файлПосле));

        const разницаПосле = Math.abs(послеПрокрутки.предсказанныйНиз - послеПрокрутки.innerHeight);
        проверить('полоска-затухание ПОСЛЕ прокрутки донизу: по-прежнему у края видимой области (±2px)',
          послеПрокрутки.высота > 0 && разницаПосле <= 2,
          'высота=' + послеПрокрутки.высота + 'px, scrollTop=' + послеПрокрутки.scrollTop +
          ', |предсказанный низ − видимая область|=' + разницаПосле.toFixed(1) + 'px');
      } else {
        проверить('на экране есть прокрутка (scrollHeight > clientHeight)', false, 'узел не нашёлся');
        проверить('полоска-затухание ДО прокрутки: ненулевая высота, низ у края видимой области (±2px)', false, 'узел не нашёлся');
        проверить('полоска-затухание ПОСЛЕ прокрутки: по-прежнему у края видимой области (±2px)', false, 'узел не нашёлся');
      }
    }

    проверить('в консоли ни одной НЕожиданной ошибки (сетевые отказы к мёртвому порту не считаем)',
      красные.length === 0, красные.join(' | '));

    await контекст.close();
    await браузер.close();
    браузер = null;
  } finally {
    if (браузер) { try { await браузер.close(); } catch (е) { /* уже закрыт */ } }
    await new Promise((р) => сервер.close(р));
  }

  return { строки, провалов, проваленныеИмена, снимки };
}

