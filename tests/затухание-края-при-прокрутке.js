/* =====================================================================
   ЗАТУХАНИЕ НИЖНЕГО КРАЯ ЭКРАНА «ИГРА С ДРУГОМ» — ДО И ПОСЛЕ ПРОКРУТКИ.

   Откуда взялась проверка. Замеры штаба 21.09: на экране «Игра с
   другом» (#экран-друга) при недоступном сервере комнат плашка беды
   (#нет-сервера-главное) стоит по вертикали 753–891 при видимой высоте
   844 — низ обрезан, а всего содержимого на экране 1333 точки. Подсказку
   «дальше есть ещё» должна давать полоска-затухание нижнего края —
   псевдоэлемент «::after» у «#экран-друга» (style.css, ~4543).

   Сомнение штаба было такое: «.экран» одновременно растянут через
   «position:absolute; inset:0» и сам прокручивается («overflow-y:auto»),
   значит абсолютный «::after» отсчитывался бы от НИЗА ВСЕГО СОДЕРЖИМОГО
   и после прокрутки уезжал бы вверх — полоска была бы только на первом
   кадре. НА МОМЕНТ НАПИСАНИЯ ЭТОЙ ПРОВЕРКИ (22.09) в style.css у правила
   уже стоит «position: fixed» — судя по комментарию рядом с правилом,
   это и есть чинка ровно этого сомнения. Проверка ниже не верит
   комментарию на слово — она измеряет по-настоящему, в живом браузере,
   на реальной геометрии, и обязана честно покраснеть, если чинка
   почему-то не работает или отвалится в будущем.

   КАК ИМЕННО ИЗМЕРЯЕМ НИЗ ПОЛОСКИ (пункты 3 и 4 задания). Не по снимку
   и не «на глаз» — псевдоэлементы не отдают getBoundingClientRect, а
   голая проверка «text position computed style не поменялся при
   прокрутке» ничего не доказывает: строка «position: fixed» в
   вычисленном стиле — это одна и та же строка текста ДО и ПОСЛЕ
   прокрутки в любом случае, она не расскажет, действительно ли браузер
   держит полоску у края экрана. Поэтому здесь — честная геометрия по
   формуле, которая различает «работает» и «не работает» ПО-РАЗНОМУ
   именно после прокрутки:

     • Если «position: fixed» — низ полоски в видимой области ВСЕГДА
       равен «innerHeight − bottom» (свойство «bottom» из CSS), потому
       что «fixed» не подчиняется прокрутке своего контейнера-предка
       (при условии, что ни один предок между «#экран-друга» и корнем
       не создаёт для неё свою систему координат — transform/filter/
       perspective/will-change/contain/backdrop-filter; в style.css на
       22.09 такого предка нет — проверено чтением, у «#приложение»
       только «position:fixed; inset:0», без трансформаций).
     • Если «position» НЕ «fixed» (например, откатили на «absolute») —
       контейнер «#экран-друга» сам не двигается при своей внутренней
       прокрутке (двигается только содержимое внутри), а абсолютный
       потомок в СВОИХ координатах контента стоит на «rect.height − bottom»
       от верха контейнера НА МОМЕНТ scrollTop=0 — и это же место в
       видимой области сдвигается на «−scrollTop» при прокрутке. Формула
       «(rect.height − bottom) − scrollTop» на scrollTop=0 даёт то же
       самое число, что и «fixed» (полоска ЕСТЬ на первом кадре — так и
       было в старой беде по описанию штаба), а после прокрутки до дна
       (scrollTop≈489 при сегодняшних числах) даёт число СИЛЬНО МЕНЬШЕ
       innerHeight — полоска «уезжает вверх». Ровно то расхождение,
       которое искал штаб, эта формула ловит по-настоящему, а не по
       касательной к тексту computed style.

   Итоговая проверка пункта: |предсказанный_низ − innerHeight| ≤ 2px,
   и высота полоски (computed height) больше нуля. Числа — в протокол.
   Плюс — те же два случая, но с ДВУМЯ снимками (пункт 5 задания) для
   смотрителя: снимок ничего не доказывает автоматике, но человек может
   глазами свериться с числами рядом.

   Дорога до экрана «Игра с другом» — та же, что у
   tests/снимок-сукна-служебных-экранов-дурака.js (заход 1, сервер
   комнат заведомо недоступен): витрина → «Дурак» → лобби → «Играть
   онлайн» → «Создать игру» → три шага → «Создать игру» → сервер не
   ответил → запасной «Игра с другом» с бедой.

   Запуск:
       node tests/затухание-края-при-прокрутке.js              — чистый прогон
       node tests/затухание-края-при-прокрутке.js --сломать    — ломающий прогон:
           портит КОПИЮ style.css во ВРЕМЕННОЙ ПАПКЕ (не в проекте!) —
           только у правила полоски высоту «24px» меняет на «0px»
           (тот же приём хранения копии, что и в
           tests/снимок-рейтинг-золото.js: временная папка + свой
           маленький http-сервер, который на дверь «/style.css» отдаёт
           испорченную копию, а остальные файлы — из настоящей папки
           проекта, читая их с диска на лету). Настоящий style.css не
           трогается ни на секунду. Проверка обязана покраснеть на
           пункте «полоска-затухание ДО прокрутки» (высота станет 0).
   ===================================================================== */

