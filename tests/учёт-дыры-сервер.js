/* Подпись initData выдуманным токеном — как в tests/онлайн-сервер.js. */
function подписать(кто) {
  const поля = new URLSearchParams();
  поля.set('user', JSON.stringify(кто));
  поля.set('auth_date', String(Math.floor(Date.now() / 1000)));
  const строки = [];
  for (const пара of поля) строки.push(пара[0] + '=' + пара[1]);
  строки.sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(ВЫДУМАННЫЙ_ТОКЕН).digest();
  поля.set('hash', crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex'));
  return поля.toString();
}

/* Заменить в тексте кусок; не нашёлся — это провал прогона, а не пропуск. */
function заменитьОбязательно(текст, что, начто, имя) {
  if (текст.indexOf(что) === -1) {
    console.log('  БЕДА ломать нечего: в сервер.js не найдено «' + имя + '»');
    process.exit(1);
  }
  return текст.replace(что, начто);
}

/**
 * Копия сервер.js во временной папке с поломкой. Пути require('./…') и
 * require('../…') переписываются на полные — копия живёт не в server/.
 */
function сделатьСломаннуюКопию(поломка) {
  // Сервер.js хранится с CRLF; копию приводим к LF, чтобы образцы ниже находились.
  let текст = fs.readFileSync(ФАЙЛ_СЕРВЕРА, 'utf8').replace(/\r\n/g, '\n');
  текст = текст.replace(/require\('(\.\.?\/[^']+)'\)/g, function (всё, имя) {
    return 'require(' + JSON.stringify(path.join(ПАПКА_СЕРВЕРА, имя)) + ')';
  });
  const строкаПосещений = "  посещения.учесть(String(кто), имяИзПодписи(целое.initData), целое.игра, Date.now());\n";
  const веткаКаталога =
    "  if (целое.каталог) {\n" +
    "    return ответить(ответ, 200, { ок: популярность.учесть(String(кто), целое.игра, целое.каталог) });\n" +
    "  }\n";
  if (поломка === 'каталог') {
    // Прежний порядок: ветка каталога уходит раньше учёта посещений.
    текст = заменитьОбязательно(текст, строкаПосещений + веткаКаталога, веткаКаталога + строкаПосещений, 'учёт посещений перед веткой каталога');
  } else if (поломка === 'гость') {
    текст = заменитьОбязательно(текст, "ИД_ГОСТЯ.test(целое.гость)", "false", 'проверка ид гостя');
  } else if (поломка === 'подпись-и-гость') {
    // Ветка гостя стоит раньше проверки подписи: поле «гость» перебивает подпись.
    // Образец привязан к имени функции: такие же строки есть и у других дверей.
    const началоПульса = "function принятьПульс(тело, ответ) {\n" +
      "  const целое = тело && typeof тело === 'object' ? тело : {};\n";
    текст = заменитьОбязательно(текст, началоПульса, началоПульса +
      "  if (typeof целое.гость === 'string' && ИД_ГОСТЯ.test(целое.гость)) {\n" +
      "    return ответить(ответ, 200, { ок: посещения.учестьГостя(целое.гость, целое.игра, Date.now()) });\n" +
      "  }\n", 'начало принятьПульс');
  } else if (поломка === 'популярность-гостя') {
    // Гость с полем «каталог» попадает в популярность — накрутка витрины.
    const строкаГостя = "      return ответить(ответ, 200, { ок: посещения.учестьГостя(целое.гость, целое.игра, Date.now()) });\n";
    текст = заменитьОбязательно(текст, строкаГостя,
      "      if (целое.каталог) популярность.учесть('1', целое.игра, целое.каталог);\n" + строкаГостя, 'учёт гостя в принятьПульс');
  } else if (поломка === 'статистика') {
    текст = заменитьОбязательно(текст, "сегодня: посещения.числаЗаДни(1, сейчас),",
      "сегодня: посещения.сводка(сейчас),", 'посещения за сегодня в /статистика');
  } else if (поломка === 'раздача') {
    текст = заменитьОбязательно(текст, "сообщение = сообщениеОПобеде(тело, кто);", "сообщение = сообщениеОПобеде(тело);", 'вызов сообщениеОПобеде с номером');
  } else {
    console.log('  БЕДА неизвестная поломка «' + поломка + '»');
    process.exit(1);
  }
  const копия = path.join(ВРЕМЕННАЯ, 'сервер-сломанный.js');
  fs.writeFileSync(копия, текст, 'utf8');
  return копия;
}

