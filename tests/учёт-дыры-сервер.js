/** Строка популярности одной игры из /статистика (или null). */
function популярностьИгры(статистика, игра) {
  const строки = Array.isArray(статистика && статистика.популярность) ? статистика.популярность : [];
  return строки.find(function (с) { return с.game === игра; }) || null;
}

/**
 * Обойти объект и собрать листья. Годный лист — только число (null тоже
 * допустим: «нет данных»). Ключи — не длиннее самого длинного ключа игры.
 * Возвращает { листьев, беды: [...] }.
 */
function обойтиЧисла(что, путь, итог) {
  итог = итог || { листьев: 0, беды: [] };
  if (что === null) { итог.листьев++; return итог; }
  if (typeof что === 'number') {
    итог.листьев++;
    if (ВСЕ_НОМЕРА.indexOf(что) !== -1) итог.беды.push(путь + ' = номер игрока');
    return итог;
  }
  if (typeof что === 'object' && !Array.isArray(что)) {
    for (const ключ of Object.keys(что)) {
      if (ключ.length > ДЛИННЕЙШИЙ_КЛЮЧ) итог.беды.push(путь + '.' + ключ + ' — ключ длиннее ключа игры');
      обойтиЧисла(что[ключ], путь + '.' + ключ, итог);
    }
    return итог;
  }
  итог.беды.push(путь + ' — не число: ' + JSON.stringify(что).slice(0, 40));
  return итог;
}

