/* Свободный порт — у системы; занятые боевые порты в любом случае мимо. */
function свободныйПорт() {
  return new Promise(function (готово, беда) {
    const пробный = net.createServer();
    пробный.once('error', беда);
    пробный.listen(0, '127.0.0.1', function () {
      const порт = пробный.address().port;
      пробный.close(function () { готово(порт); });
    });
  });
}

