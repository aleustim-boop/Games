/* =====================================================================
   Автопрогон правил по ТРЁМ УРОВНЯМ СОПЕРНИКА.

   Зачем нужен отдельно от «автопрогон-правил.js»: тот файл гоняет только
   обычного бота. А уровни добавили позже, и вместе с ними в правила залезли
   новой рукой — значит, каждый уровень надо прогнать заново и проверить,
   что он не научился жульничать и не вешает партию.

   Что проверяется после КАЖДОГО хода:
     - все 36 карт на месте, ни одна не размножилась и не пропала;
     - на столе не больше шести пар;
     - каждая побитая карта побита по правилам (старше той же масти или козырь);
     - подкинуть можно только достоинство, которое уже лежит на столе;
     - пока колода не пуста, новый заход начинается с полными руками по 6;
     - пока партия не окончена — всегда есть кто ходит;
     - ход обязан что-то менять, иначе игра стоит на месте;
     - в конце проигравший определён верно.

   Ещё считается доля ничьих по каждому уровню — её просили перепроверить
   независимо от разработчика.

   Запуск: node tests/автопрогон-уровней.js [партий на каждую пару уровней]
   ===================================================================== */

'use strict';

const игра = require(require('path').join(__dirname, '..', 'js', 'game.js'));

const ПАРТИЙ = Number(process.argv[2]) || 400;
const ПРЕДЕЛ_ХОДОВ = 500;

/* Свой генератор случайных чисел — чтобы любую поломку можно было повторить
   по номеру партии. Тот же приём, что и в остальных наших тестах. */
let зерно = 1;
Math.random = function () {
  зерно = (зерно * 1103515245 + 12345) % 2147483648;
  return зерно / 2147483648;
};

const ПОЛНАЯ_КОЛОДА = игра.собратьКолоду()
  .map(function (к) { return к.имя + к.масть; })
  .sort()
  .join(' ');

function имя(к) { return к.имя + к.масть; }

function всеКарты(п) {
  const список = п.колода.concat(п.руки.человек, п.руки.бот, п.отбой);
  for (const пара of п.стол) {
    список.push(пара.атака);
    if (пара.защита) список.push(пара.защита);
  }
  return список;
}

function снимокСтола(п) {
  return п.стол.map(function (пара) {
    return { атака: имя(пара.атака), защита: пара.защита ? имя(пара.защита) : null };
  });
}

function достоинстваСтола(п) {
  const набор = new Set();
  for (const пара of п.стол) {
    набор.add(пара.атака.имя);
    if (пара.защита) набор.add(пара.защита.имя);
  }
  return набор;
}

/** Все проверки состояния разом. Возвращает список бед (пустой — значит порядок). */
function проверитьСостояние(п) {
  const беды = [];
  const карты = всеКарты(п);

  if (карты.length !== 36) беды.push('карт в партии ' + карты.length + ' вместо 36');
  const поИмени = карты.map(имя).sort().join(' ');
  if (поИмени !== ПОЛНАЯ_КОЛОДА) беды.push('набор карт испортился (появились двойники или что-то пропало)');

  const ссылки = new Set();
  for (const к of карты) {
    if (ссылки.has(к)) { беды.push('карта ' + имя(к) + ' лежит сразу в двух местах'); break; }
    ссылки.add(к);
  }

  if (п.стол.length > 6) беды.push('на столе ' + п.стол.length + ' пар — больше шести');

  for (const пара of п.стол) {
    if (пара.защита && !игра.бьёт(пара.защита, пара.атака, п.козырь)) {
      беды.push('карта ' + имя(пара.атака) + ' побита неподходящей ' + имя(пара.защита) +
        ' (козырь ' + п.козырь + ')');
    }
  }

  if (п.колода.length > 0 && п.колода[п.колода.length - 1] !== п.козырнаяКарта) {
    беды.push('козырная карта перестала лежать под колодой');
  }

  if (!п.завершена && п.колода.length > 0 && п.стол.length === 0) {
    if (п.руки.человек.length < 6 || п.руки.бот.length < 6) {
      беды.push('колода не пуста (' + п.колода.length + '), а руки недобраны: человек ' +
        п.руки.человек.length + ', бот ' + п.руки.бот.length);
    }
  }

  if (!п.завершена && игра.ктоХодит(п) === null) беды.push('партия не окончена, а ходить некому');

  if (п.завершена) {
    const чПуст = п.руки.человек.length === 0;
    const бПуст = п.руки.бот.length === 0;
    if (п.колода.length > 0) беды.push('партия окончена, а в колоде ещё ' + п.колода.length + ' карт');
    if (п.стол.length > 0) беды.push('партия окончена, а на столе остались карты');
    let ожидаемый;
    if (чПуст && бПуст) ожидаемый = 'ничья';
    else if (чПуст) ожидаемый = 'бот';
    else if (бПуст) ожидаемый = 'человек';
    else ожидаемый = 'никто (у обоих есть карты)';
    if (п.результат !== ожидаемый) {
      беды.push('проигравший определён неверно: записано «' + п.результат + '», по рукам выходит «' +
        ожидаемый + '»');
    }
  }

  return беды;
}

/** Не подкинули ли карту достоинства, которого на столе не было. */
function проверитьПодкидывание(доСнимок, доДостоинства, п) {
  const беды = [];
  const после = снимокСтола(п);
  if (после.length <= доСнимок.length) return беды;
  for (let i = доСнимок.length; i < после.length; i++) {
    if (доСнимок.length === 0 && i === 0) continue;      // первая карта захода — любая
    const достоинство = после[i].атака.slice(0, -1);
    if (!доДостоинства.has(достоинство)) {
      беды.push('подкинута карта ' + после[i].атака + ' чужого достоинства (на столе были: ' +
        Array.from(доДостоинства).join(', ') + ')');
    }
  }
  return беды;
}

/* ---------------------------------------------------------------------
   Одна партия: за «человека» и за «бота» ходят боты заданных уровней
   --------------------------------------------------------------------- */

function сыгратьПартию(уровеньЧеловека, уровеньБота) {
  // Уровень партии — тот, которым играет бот (как в настоящей игре).
  const п = игра.создатьПартию(уровеньБота);
  const журнал = [];

  const первые = проверитьСостояние(п);
  if (первые.length) return { ошибки: первые.map(function (т) { return 'при раздаче: ' + т; }), журнал: журнал };

  let ходов = 0;
  while (!п.завершена) {
    if (++ходов > ПРЕДЕЛ_ХОДОВ) {
      return {
        ошибки: ['партия зависла: ' + ПРЕДЕЛ_ХОДОВ + ' ходов без конца. Фаза «' + игра.фаза(п) +
          '», ходит ' + игра.ктоХодит(п) + ', в колоде ' + п.колода.length +
          ', на столе ' + п.стол.length + ', руки: человек ' + п.руки.человек.length +
          ', бот ' + п.руки.бот.length],
        журнал: журнал.slice(-20)
      };
    }

    const кто = игра.ктоХодит(п);
    const уровень = кто === 'человек' ? уровеньЧеловека : уровеньБота;

    const фазаДо = игра.фаза(п);
    const снимокДо = снимокСтола(п);
    const достоинстваДо = достоинстваСтола(п);
    const рукиДо = { ч: п.руки.человек.length, б: п.руки.бот.length };
    const колодаДо = п.колода.length;

    const действие = игра.ходБота(п, кто, уровень);
    журнал.push(кто + '/' + уровень + ': ' + действие + ' (фаза «' + фазаДо + '»)');

    if (действие === 'не его ход') {
      return { ошибки: ['бот отказался ходить в свою очередь, фаза «' + фазаДо + '»'], журнал: журнал.slice(-20) };
    }

    const беды = проверитьСостояние(п);
    беды.push.apply(беды, проверитьПодкидывание(снимокДо, достоинстваДо, п));

    const ничегоНеИзменилось = !п.завершена &&
      игра.фаза(п) === фазаДо &&
      JSON.stringify(снимокСтола(п)) === JSON.stringify(снимокДо) &&
      п.руки.человек.length === рукиДо.ч &&
      п.руки.бот.length === рукиДо.б &&
      п.колода.length === колодаДо;
    if (ничегоНеИзменилось) беды.push('ход «' + действие + '» ничего не изменил — партия стоит на месте');

    if (беды.length) return { ошибки: беды, журнал: журнал.slice(-20) };
  }

  return { ошибки: [], журнал: журнал, результат: п.результат, ходов: ходов };
}

/* ---------------------------------------------------------------------
   Прогон одной пары уровней
   --------------------------------------------------------------------- */

function прогон(название, уровеньЧеловека, уровеньБота, партий, смещение) {
  const итог = {
    название: название, сыграно: 0,
    победаЧеловека: 0, победаБота: 0, ничьих: 0,
    ходовВсего: 0, ошибки: []
  };
  for (let н = 1; н <= партий; н++) {
    зерно = (н * 7919 + смещение) % 2147483648;
    const р = сыгратьПартию(уровеньЧеловека, уровеньБота);
    итог.сыграно++;
    итог.ходовВсего += р.ходов || 0;
    if (р.ошибки.length) {
      итог.ошибки.push({ номер: н, ошибки: р.ошибки, журнал: р.журнал });
      if (итог.ошибки.length >= 3) break;
      continue;
    }
    if (р.результат === 'ничья') итог.ничьих++;
    else if (р.результат === 'бот') итог.победаЧеловека++;   // дурак — бот
    else итог.победаБота++;                                   // дурак — человек
  }
  return итог;
}

/* ---------------------------------------------------------------------
   Проверка, что незнакомый уровень не ломает игру
   --------------------------------------------------------------------- */

function проверитьМусорныеУровни() {
  const беды = [];
  const мусор = [undefined, null, '', 'ЛЁГКИЙ', 'hard', 0, 42, {}, [], 'обычный ', true];
  for (const значение of мусор) {
    зерно = 555;
    let п;
    try {
      п = игра.создатьПартию(значение);
    } catch (ошибка) {
      беды.push('создатьПартию(' + JSON.stringify(значение) + ') упала: ' + ошибка.message);
      continue;
    }
    if (игра.СЛОЖНОСТИ.indexOf(п.сложность) === -1) {
      беды.push('создатьПартию(' + JSON.stringify(значение) + ') записала непонятный уровень «' + п.сложность + '»');
    }
    // И партия с таким уровнем должна доиграться до конца.
    let шагов = 0;
    try {
      while (!п.завершена && шагов++ < ПРЕДЕЛ_ХОДОВ) игра.ходБота(п, игра.ктоХодит(п), значение);
    } catch (ошибка) {
      беды.push('ход с уровнем ' + JSON.stringify(значение) + ' упал: ' + ошибка.message);
      continue;
    }
    if (!п.завершена) беды.push('партия с уровнем ' + JSON.stringify(значение) + ' не закончилась');
  }
  return беды;
}

