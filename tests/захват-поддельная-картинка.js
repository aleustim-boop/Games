'use strict';
/* =====================================================================
   Поддельная Image для node-проверок «Захвата» (в node её нет, а экран и онлайн
   с Г1б грузят рисунки карты). Общий помощник: подключается через require.

   поставитьКартинки(окно, битые) кладёт в окно песочницы конструктор Image.
     - размер берётся из РАЗМЕРЫ карты-вида (листы сот и стрелок — по имени, остальные — по ключу);
       карта-вид к этому часу уже должна лежать в окне (читается лениво, при загрузке);
     - onload зовётся асинхронно (обещание), так что проверке нужен await;
     - битые — пути, для которых вместо onload зовётся onerror (как 404 в браузере);
     - учёт.создано — сколько Image создано; учёт.пути — какие пути просили по порядку;
     - учёт.держать = true — ответы копятся, а учёт.отпустить() выдаёт их разом
       (так проверка делает «загрузка пришла поздно»).
   ===================================================================== */

function поставитьКартинки(окно, битые) {
  const учёт = { создано: 0, пути: [], битые: битые || [], держать: false, отложено: [] };
  учёт.отпустить = () => { учёт.отложено.splice(0).forEach(дело => дело()); };

  function размерПоПути(путь) {
    const имя = путь.replace(/^img\/захват\//, '').replace(/\.webp$/, '');
    const Р = окно.ЗахватКартаВид.РАЗМЕРЫ;
    if (/-лёгкая$/.test(имя)) return Р.сотаЛёгкая;
    if (/^сота-/.test(имя)) return Р.сота;
    if (/^стрелки-/.test(имя)) return Р.стрелки;
    return Р[имя] || { ширина: 1, высота: 1 };   // неизвестное имя — размер-пустышка: загрузчик сам покраснеет в консоли
  }

  окно.Image = function () { учёт.создано++; };
  Object.defineProperty(окно.Image.prototype, 'src', {
    set(путь) {
      this._путь = путь;
      учёт.пути.push(путь);
      const закончить = () => {
        if (учёт.битые.indexOf(путь) !== -1) { if (this.onerror) this.onerror(); return; }
        const р = размерПоПути(путь);
        this.width = р.ширина;
        this.height = р.высота;
        if (this.onload) this.onload();
      };
      if (учёт.держать) учёт.отложено.push(закончить);
      else Promise.resolve().then(закончить);
    }
  });
  return учёт;
}

/** Дать обещаниям дойти: несколько настоящих тиков (поддельные часы тут ни при чём). */
async function дождатьсяКартинок() {
  for (let н = 0; н < 12; н++) await new Promise(готово => setImmediate(готово));
}

module.exports = { поставитьКартинки, дождатьсяКартинок };
