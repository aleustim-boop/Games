'use strict';

/* =====================================================================
   УБОРКА УСТАРЕВШИХ ЗАПИСЕЙ ИГРОКОВ В server/билеты.js.

   Что проверяем. server/билеты.js держит Map «игроки»: номер Telegram →
   когда он последний раз брал и сдавал билет на партию с ботом. Запись
   заводилась на каждый новый номер и жила до перезапуска сервера — при
   живом сервере она только росла месяцами. Теперь модуль сам убирает
   запись, если с последней выдачи И сдачи прошло больше отведённого
   срока (server/билеты.js, ЗАПИСЬ_ИГРОКА_ЖИВЁТ) — он взят с запасом
   поверх суток, по которым считается «не больше двадцати сдач в сутки»:
   это самый долгий из сроков, что держат запись живой, остальные
   (билет, замедление выдачи и сдачи) короче и истекают раньше. Уборка
   ленивая: зовётся при каждой выдаче билета, но реально проходит по
   Map не чаще раза в УБОРКА_ИГРОКОВ_НЕ_ЧАЩЕ — дёшево при живом трафике.

   Часы уборка берёт из того же довода «сейчас», что уже был у выдать()
   и погасить() — отдельного способа подменить время заводить не
   пришлось.

   Сценарии:
     0) инвариант ЗАПИСЬ_ИГРОКА_ЖИВЁТ > СУТКИ — если окно когда-нибудь
        сделают короче суток, лимит «не больше двадцати сдач в сутки»
        начнёт слетать раньше времени (запись сотрут посреди тех же
        суток, счётчик сдачЗаДень обнулится без смены календарного дня);
     1) запись без движения дольше ЗАПИСЬ_ИГРОКА_ЖИВЁТ — уборка,
        спровоцированная выдачей билета другому игроку, стирает её;
     2) запись моложе окна — уборка её не трогает, и замедление
        «билет не чаще раза в 10 секунд» продолжает работать как раньше
        (проверяем не только отказ, но и его причину словами);
     3) «выдан» давно устарел, а «сдан» — свежий (билет недавно
        погасили): запись живёт по более позднему времени, а не
        стирается раньше срока — убеждаемся, что чистка смотрит на ОБА
        поля, а не только на «выдан».

   ЛОМАЮЩИЙ ЗАПУСК (обязан покраснеть):
       node tests/билеты-чистка.js --папка=<путь до копии server/>
   Путь ведёт на ПОРЧЕНУЮ копию server/ (билеты.js с выключенной
   уборкой, рейтинг.js и js/game.js рядом, как требуют её же require).
   Красным падает и копия с окном короче суток (например 4 часа вместо
   двух суток) — на ней проверка 0 ловит слишком короткое ЗАПИСЬ_ИГРОКА_ЖИВЁТ
   ещё до того, как дело дойдёт до временных сценариев.
   Настоящие файлы проекта этот файл не трогает и не портит — копию и
   поломку готовит тот, кто ломающий запуск проводит.

   Обычный запуск:
       node tests/билеты-чистка.js
   ===================================================================== */

const path = require('path');
const os = require('os');
const fs = require('fs');

const КОРЕНЬ = path.join(__dirname, '..');

const аргПапка = process.argv.find(function (а) { return а.startsWith('--папка='); });
const ПАПКА_СЕРВЕРА = аргПапка ? аргПапка.slice('--папка='.length) : path.join(КОРЕНЬ, 'server');

/* Рейтинг (его требует билеты.js) не должен даже краем задеть боевые
   данные — уводим его файлы в свою временную папку, как учит
   server/папка-данных.js. Ставим переменную до require, но она и так
   читается при каждом обращении — порядок здесь не играет роли. */
const ПАПКА_ДАННЫХ = path.join(os.tmpdir(), 'билеты-чистка-данные-' + process.pid);
process.env.ДАННЫЕ_ИГРЫ = ПАПКА_ДАННЫХ;

let проверок = 0;
let провалов = 0;
function зелёный(текст) { проверок++; console.log('  ✓ ' + текст); }
function красный(текст) { проверок++; провалов++; console.log('  ✗ ' + текст); }
function проверить(условие, текст) { if (условие) зелёный(текст); else красный(текст); }

/* Метка времени вне реальных часов машины — сценарии двигают её сами. */
const Т_НОЛЬ = 1800000000000;

try {
  const билеты = require(path.join(ПАПКА_СЕРВЕРА, 'билеты.js'));

  /* ===================================================================
     Сценарий 0: окно уборки записи заведомо длиннее суток — иначе лимит
     «не больше двадцати сдач в сутки» слетит раньше положенного срока.
     =================================================================== */
  проверить(typeof билеты.СУТКИ === 'number' && typeof билеты.ЗАПИСЬ_ИГРОКА_ЖИВЁТ === 'number' &&
    билеты.ЗАПИСЬ_ИГРОКА_ЖИВЁТ > билеты.СУТКИ,
    '0) окно уборки записи игрока (ЗАПИСЬ_ИГРОКА_ЖИВЁТ=' + билеты.ЗАПИСЬ_ИГРОКА_ЖИВЁТ +
    ') дольше суток (СУТКИ=' + билеты.СУТКИ + ')');

  /* ===================================================================
     Сценарий 1: запись без движения дольше окна — уборка стирает.
     =================================================================== */
  (function сценарий1() {
    билеты.забытьВсё();
    const A = 910000001, B = 910000002;
    const выд = билеты.выдать(A, 'дурак', 'обычный', Т_НОЛЬ);
    проверить(выд && выд.ок === true, '1) билет выдан игроку A');
    проверить(билеты.сколькоИгроков() === 1, '1) запись игрока A заведена');

    const T1 = Т_НОЛЬ + билеты.ЗАПИСЬ_ИГРОКА_ЖИВЁТ + 1000;
    билеты.выдать(B, 'дурак', 'обычный', T1); // ленивая уборка спрятана внутри выдать()
    проверить(билеты.сколькоИгроков() === 1,
      '1) за окном запись игрока A убрана уборкой (осталась только B), записей сейчас: ' + билеты.сколькоИгроков());
  })();

  /* ===================================================================
     Сценарий 2: запись внутри окна не трогаем, замедление выдачи держит.
     =================================================================== */
  (function сценарий2() {
    билеты.забытьВсё();
    const A = 920000001, B = 920000002;
    билеты.выдать(A, 'дурак', 'обычный', Т_НОЛЬ);

    const throttleОтвет = билеты.выдать(A, 'дурак', 'обычный', Т_НОЛЬ + 1000);
    проверить(throttleОтвет && throttleОтвет.ок === false &&
      typeof throttleОтвет.причина === 'string' && throttleОтвет.причина.indexOf('десять секунд') !== -1,
      '2) «билет не чаще раза в 10 секунд» по-прежнему держит, причина: ' + (throttleОтвет && throttleОтвет.причина));

    const T1 = Т_НОЛЬ + билеты.УБОРКА_ИГРОКОВ_НЕ_ЧАЩЕ + 1000; // хватит для ленивой чистки, но меньше окна
    билеты.выдать(B, 'дурак', 'обычный', T1);
    проверить(билеты.сколькоИгроков() === 2,
      '2) запись игрока A внутри окна уборка не тронула, записей: ' + билеты.сколькоИгроков());
  })();

  /* ===================================================================
     Сценарий 3: «выдан» устарел, «сдан» — нет: смотрим на оба поля.
     =================================================================== */
  (function сценарий3() {
    билеты.забытьВсё();
    const A = 930000001, B = 930000002;
    const выд = билеты.выдать(A, 'дурак', 'обычный', Т_НОЛЬ);
    const Tсдача = Т_НОЛЬ + выд.партияНеКорочеСекунд * 1000 + 1000;
    const пог = билеты.погасить(A, выд.билет, 'поражение', 'Проверка', Tсдача);
    проверить(пог && пог.ок === true, '3) билет погашен (партия учтена, исход «поражение» — очков не тратит)');

    const T2 = Т_НОЛЬ + билеты.ЗАПИСЬ_ИГРОКА_ЖИВЁТ + 500; // старше окна от «выдан», моложе — от «сдан»
    билеты.выдать(B, 'дурак', 'обычный', T2);
    проверить(билеты.сколькоИгроков() === 2,
      '3) запись жива по более позднему «сдан», уборка её не стёрла раньше срока, записей: ' + билеты.сколькоИгроков());
  })();
} catch (беда) {
  красный('проверка оборвалась: ' + беда.message);
  console.log(беда.stack);
}

try { fs.rmSync(ПАПКА_ДАННЫХ, { recursive: true, force: true }); } catch (е) { /* нарочно молчим — временная папка необязательна */ }

console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
process.exit(провалов > 0 ? 1 : 0);
