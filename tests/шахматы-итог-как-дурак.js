'use strict';

/* Проверка без браузера: итог партии шахмат и стрелка шага «Игра онлайн»
   сделаны как у дурака (владелец 02.10, этап Ш-2). Читает разметку и код
   как текст.

   Запуск:  node tests/шахматы-итог-как-дурак.js [шахматы.html] [шахматы-экран.js]
   Пути нужны для «красного» запуска: проверка на КОПИЯХ, где поломку вернули,
   обязана упасть. Настоящие файлы портить нельзя.

   Ноль найденных узлов — провал, а не пропуск. */

const fs = require('fs');
const path = require('path');

const корень = path.join(__dirname, '..');
const путьHtml = process.argv[2] ? path.resolve(process.argv[2]) : path.join(корень, 'шахматы.html');
const путьJs = process.argv[3] ? path.resolve(process.argv[3]) : path.join(корень, 'js', 'шахматы-экран.js');
const html = fs.readFileSync(путьHtml, 'utf8');
const код = fs.readFileSync(путьJs, 'utf8');

let провалов = 0;
let всего = 0;
function проверить(условие, слова) {
  всего++;
  if (!условие) провалов++;
  console.log((условие ? '  ок      ' : '  ПРОВАЛ  ') + слова);
}

/** Кусок текста от начала до конца (включительно); пусто, если не нашли. */
function кусок(текст, начало, конец) {
  const от = текст.indexOf(начало);
  if (от === -1) return '';
  const до = текст.indexOf(конец, от);
  return до === -1 ? '' : текст.slice(от, до + конец.length);
}

console.log('Страница: ' + путьHtml);
console.log('Код: ' + путьJs);

console.log('\n1. Итог партии');
const итог = кусок(html, '<section id="экран-итога"', '</section>');
проверить(итог.length > 0, 'плашка «экран-итога» найдена');
/** Кнопка с этим id и подписью внутри плашки итога. */
function кнопкаИтога(id, подпись) {
  const к = кусок(итог, '<button id="' + id + '"', '</button>');
  return к.length > 0 && к.indexOf('>' + подпись + '<') !== -1;
}
проверить(кнопкаИтога('кнопка-ещё', 'Играть ещё'), 'есть «Играть ещё»');
проверить(кнопкаИтога('кнопка-реванш', 'Реванш'), 'есть «Реванш» в разметке (не строится кодом)');
проверить(кнопкаИтога('кнопка-ещё-с-ботом', 'Сыграть с ботом'), 'есть «Сыграть с ботом»');
проверить(кнопкаИтога('кнопка-похвастаться', 'Похвастаться'), 'есть «Похвастаться»');
проверить(/id="кнопка-похвастаться"[^>]*кнопка--похвастаться/.test(итог), '«Похвастаться» с общим классом кнопка--похвастаться');
проверить(кнопкаИтога('кнопка-рекорды-итог', 'Рекорды'), 'есть «Рекорды»');
проверить(кнопкаИтога('кнопка-в-меню-итог', 'В меню'), 'есть «В меню»');
проверить(/<p id="итог-рейтинга"/.test(итог), 'есть место для «+N к рейтингу» (итог-рейтинга)');
проверить(!/style=/.test(итог), 'своего вида на плашке нет (style=)');

// Порядок как у дурака: ещё → реванш → с ботом → похвастаться → рекорды → в меню
const порядок = ['кнопка-ещё"', 'кнопка-реванш"', 'кнопка-ещё-с-ботом"', 'кнопка-похвастаться"', 'кнопка-рекорды-итог"', 'кнопка-в-меню-итог"'];
const места = порядок.map(function (имя) { return итог.indexOf('id="' + имя); });
проверить(места.every(function (м) { return м !== -1; }) && места.every(function (м, и) { return и === 0 || м > места[и - 1]; }),
  'порядок кнопок как у дурака: ещё, реванш, с ботом, похвастаться, рекорды, в меню');

console.log('\n2. Код итога');
проверить(/getElementById\('кнопка-в-меню-итог'\)/.test(код) && /кнопкаВМенюИтог\.addEventListener\('click', уйтиНаВитрину\)/.test(код), '«В меню» привязана к уйтиНаВитрину');
проверить(/getElementById\('кнопка-ещё-с-ботом'\)/.test(код) && /кнопкаЕщёСБотом\.addEventListener/.test(код), '«Сыграть с ботом» привязана');
проверить(/кнопкаЕщёСБотом\.classList\.toggle\('скрыт', !другУшёл\)/.test(код), '«Сыграть с ботом» показывается, когда соперник ушёл');
проверить(/window\.Сеть\.похвастаться\(/.test(код), '«Похвастаться» зовёт общую дверь Сеть.похвастаться');
проверить(/ОчкиРейтинга\.словаИтога\(/.test(код) && /getElementById\('итог-рейтинга'\)/.test(код), 'строка рейтинга пишется через ОчкиРейтинга.словаИтога');
проверить(!/document\.createElement\('button'\)/.test(кусок(код, 'РЕВАНШ ПО СЕТИ', 'ЭКРАНЫ ПО ИМЕНИ')), 'реванш больше не строится кодом');

console.log('\n3. Стрелка Telegram на шаге «Игра онлайн»');
const таблица = кусок(код, 'const КНОПКА_НАЗАД_НА_ЭКРАНЕ_СЕТИ = {', '};');
проверить(таблица.length > 0, 'таблица КНОПКА_НАЗАД_НА_ЭКРАНЕ_СЕТИ найдена');
проверить(/'экран-лобби-онлайн':\s*'кнопка-лобби-онлайн-назад'/.test(таблица), 'экран-лобби-онлайн → кнопка-лобби-онлайн-назад');
проверить(/id="кнопка-лобби-онлайн-назад"/.test(html), 'кнопка «кнопка-лобби-онлайн-назад» есть в разметке');
const списокЛиста = /экраныСЛистом:\s*\[([^\]]*)\]/.exec(код);
проверить(Boolean(списокЛиста) && списокЛиста[1].indexOf("'экран-лобби-онлайн'") !== -1, 'экран-лобби-онлайн в экраныСЛистом (пункт «Настройки»)');

console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
process.exit(провалов ? 1 : 0);
