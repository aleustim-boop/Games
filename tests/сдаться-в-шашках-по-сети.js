/** Поднять node-процесс и дождаться в его stdout приметы готовности. */
function поднять(файл, доводыКоманды, приметаГотовности) {
  return new Promise(function (готово, беда) {
    const дитя = spawn('node', [файл].concat(доводыКоманды));
    let вывод = '';
    const срок = setTimeout(function () {
      дитя.kill();
      беда(new Error('процесс ' + файл + ' не поднялся за 15 секунд, вывод: ' + вывод));
    }, 15000);
    дитя.stdout.on('data', function (кусок) {
      вывод += кусок;
      if (приметаГотовности.test(вывод)) { clearTimeout(срок); готово(дитя); }
    });
    дитя.stderr.on('data', function (кусок) { вывод += кусок; });
    дитя.on('error', беда);
    дитя.on('exit', function (код) {
      if (код !== null && код !== 0) беда(new Error('процесс ' + файл + ' упал с кодом ' + код + ': ' + вывод));
    });
  });
}

/** Обычный HTTP-запрос к серверу комнат — тем же приёмом, что в шашки-по-сети-автопрогон.js. */
function запросКомнатам(путь, тело) {
  return new Promise(function (готово, беда) {
    const текст = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const обращение = http.request({
      host: '127.0.0.1', port: ПОРТ_КОМНАТ, method: 'POST', path: encodeURI(путь),
      headers: { 'Content-Type': 'application/json', 'Content-Length': текст.length }
    }, function (ответ) {
      let куски = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (к) { куски += к; });
      ответ.on('end', function () {
        let данные = {};
        try { данные = JSON.parse(куски); } catch (сбой) { данные = { сыройОтвет: куски }; }
        готово({ номер: ответ.statusCode, данные: данные });
      });
    });
    обращение.setTimeout(10000, function () { обращение.destroy(new Error('сервер не ответил на ' + путь)); });
    обращение.on('error', беда);
    обращение.end(текст);
  });
}

function здоровье() {
  return new Promise(function (готово, беда) {
    http.get({ host: '127.0.0.1', port: ПОРТ_КОМНАТ, path: encodeURI('/здоровье') }, function (ответ) {
      let к = '';
      ответ.on('data', function (ч) { к += ч; });
      ответ.on('end', function () { try { готово(JSON.parse(к)); } catch (сбой) { беда(new Error('не JSON')); } });
    }).on('error', беда);
  });
}

/** Тап пальцем: сперва «уже подсвечено, куда идти», иначе «поднять свою шашку». Тот же приём, что в шашки-партия-пальцем.js. */
async function тапнуть(страница) {
  return страница.evaluate(() => {
    const случайный = (список) => список[Math.floor(Math.random() * список.length)];
    const куда = document.querySelectorAll('.поле--можно, .поле--можно-бой');
    if (куда.length > 0) { случайный(Array.from(куда)).click(); return 'ход'; }
    const свои = document.querySelectorAll('.фишка--может-ходить');
    if (свои.length > 0) { случайный(Array.from(свои)).parentElement.click(); return 'поднял'; }
    return 'нечего';
  });
}

/** Довести один полный ход (поднять → сходить) на одной странице, если сейчас её очередь. */
async function попытатьсяСходить(страница, попыток) {
  for (let i = 0; i < (попыток || 4); i++) {
    const что = await тапнуть(страница);
    if (что === 'ход') return true;
    if (что === 'нечего') return false;
    await спать(150);
  }
  return false;
}

function снимокДоски(страница) {
  return страница.evaluate(() => {
    const поля = Array.from(document.querySelectorAll('#доска .поле'));
    return поля.map(function (п) {
      const ф = п.querySelector('.фишка');
      if (!ф) return '.';
      return ф.classList.contains('фишка--белая') ? 'б' : 'ч';
    }).join('');
  });
}

async function читатьКнопкуСдаться(страница) {
  return страница.evaluate(() => {
    const кнопка = document.getElementById('кнопка-сдаться');
    if (!кнопка) return null;
    return {
      естьВДоме: true,
      видна: кнопка.offsetParent !== null,
      скрыта: кнопка.classList.contains('скрыт'),
      disabled: кнопка.disabled,
      текст: (кнопка.textContent || '').trim()
    };
  });
}

async function читатьИтог(страница) {
  return страница.evaluate(() => ({
    видимаПлашка: document.getElementById('экран-итога').classList.contains('экран--виден'),
    заголовок: (document.getElementById('заголовок-итога') || {}).textContent || '',
    причина: (document.getElementById('причина-итога') || {}).textContent || ''
  }));
}

/** Код и пропуск текущей сетевой комнаты — читаем из localStorage той же дверью, что и сама игра (ключ «room_<латиница игры>»). */
async function прочитатьПропуск(страница) {
  return страница.evaluate(() => {
    for (const ключ of Object.keys(window.localStorage)) {
      if (ключ.indexOf('room_') !== 0) continue;
      try {
        const разобранное = JSON.parse(window.localStorage.getItem(ключ));
        if (разобранное && разобранное.код && разобранное.пропуск) return разобранное;
      } catch (сбой) { /* пропускаем */ }
    }
    return null;
  });
}

