function случай50(Р) {
  const всеИмена = ['Аня', 'Боря', 'Вика', 'Гена', 'Дина', 'Егор'];
  const уровни = ['лёгкий', 'обычный', 'сложный'];
  const учёт = { раундов: 0, шаговСоСчётом: 0, перемен: 0, причин: 0, пачки: 0, плотно: 0 };
  const видов = {};
  const плохие = [];
  [2, 3, 4, 5, 6].forEach((мест) => {
    for (let з = 1; з <= 4; з++) {
      const зерно = мест * 1000 + з;
      const случай = генератор(зерно);
      const имена = {};
      всеИмена.slice(0, мест).forEach((и) => { имена[и] = и; });
      let партия = Правила.новаяПартия({ игроки: Object.keys(имена) }, случай);
      let раундовПартии = 0;
      while (!партия.завершена && раундовПартии < 200) {
        раундовПартии++;
        // Изредка кто-то сдаётся — проверяем шаг 0 (области сдавшегося серые с первого снимка).
        const живые = партия.игроки.filter((к) => Правила.вИгре(партия, к));
        if (живые.length > 2 && случай() < 0.03) {
          Правила.сдаться(партия, живые[Math.floor(случай() * живые.length)]);
          if (партия.завершена) break;
        }
        const черновики = {};
        партия.игроки.forEach((к, и) => {
          if (Правила.вИгре(партия, к)) черновики[к] = Бот.решить(партия, к, уровни[(з + и) % 3], случай);
        });
        const войскаДо = партия.войска.slice();
        const хозяеваДо = партия.хозяева.slice();
        const р = Правила.разобратьРаунд(партия, черновики, случай);
        const я = партия.игроки[Math.floor(случай() * партия.игроки.length)];
        const плотно = случай() < 0.5;
        const вход = {
          события: р.события, раунд: р.раунд, карта: партия.карта, имена: имена, я: я, плотно: плотно,
          хозяеваДо: хозяеваДо, хозяеваПосле: р.партия.хозяева, войскаДо: войскаДо
        };
        учёт.раундов++;
        if (плотно) учёт.плотно++;
        р.события.forEach((с) => { видов[с.вид + (с.исход ? ':' + с.исход : '')] = true; });
        const беды = разобратьСчёт(Р, вход, р.партия, учёт);
        беды.forEach((б) => плохие.push('зерно ' + зерно + ', раунд ' + р.раунд + ', я ' + я + ': ' + б));
        партия = р.партия;
      }
    }
  });
  // «Разошлись» (10 обменов, обе колонны живы) боты почти не дают: на 2600 раундах — ни разу. Этот
  // исход — подставной раунд: обе колонны идут домой, пилюли гаснут возвратами в том же порядке.
  разошлисьПодставой(Р, учёт).forEach((б) => плохие.push('подставной «разошлись»: ' + б));
  видов['встречный:разошлись'] = true;
  плохие.slice(0, 12).forEach((б) => console.log('    ' + б));
  проверить(плохие.length === 0, 'случай 50: бед в живом счёте ' + плохие.length + ' (первые выше)');
  проверить(учёт.раундов >= 200, 'случай 50: раундов ' + учёт.раундов + ', ждали не меньше 200');
  проверить(учёт.перемен > 0 && учёт.шаговСоСчётом > учёт.раундов, 'случай 50: перемен в счёте ' + учёт.перемен + ' (ноль найденного — провал)');
  // Каждый вид события, меняющий счёт, должен встретиться хоть раз — иначе его ветку никто не проверил.
  ['сдался', 'расстановка', 'приказ', 'перевод', 'встречный:прошла', 'встречный:разошлись', 'удар:взята',
    'удар:отбит', 'удар:все погибли', 'возврат', 'рассеялись'].forEach((вид) => {
    проверить(!!видов[вид], 'случай 50: ни разу не встретилось событие «' + вид + '» (ноль найденного — провал)');
  });
  проверить(учёт.пачки > 0, 'случай 50: ни одного раунда с пачками боёв');
  проверить(учёт.причин > 0, 'случай 50: ни одной причины боя в настоящих раундах');
  console.log('  случай 50: раундов ' + учёт.раундов + ' (плотно ' + учёт.плотно + '), шагов со счётом ' + учёт.шаговСоСчётом +
    ', перемен чисел ' + учёт.перемен + ', с пачками ' + учёт.пачки + ', причин ' + учёт.причин);
}

