function сломать() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-раскрытие-счёт-'));
  const исходный = fs.readFileSync(ФАЙЛ, 'utf8');
  try {
    // Сначала целый файл обязан пройти — иначе «покраснение» ничего не доказывает.
    const целый = spawnSync(process.execPath, [__filename], { encoding: 'utf8' });
    проверить(целый.status === 0, 'сломать: целый файл не проходит проверку, ломать нечего');
    ПОРЧИ.forEach((порча, н) => {
      const место = исходный.indexOf(порча.было);
      проверить(место !== -1, 'порча «' + порча.имя + '»: нечего портить, узел «' + порча.было + '» не найден');
      if (место === -1) return;
      const копия = path.join(папка, 'копия-' + н + '.js');
      fs.writeFileSync(копия, исходный.slice(0, место) + порча.стало + исходный.slice(место + порча.было.length));
      const вышло = spawnSync(process.execPath, [__filename, '--файл', копия], { encoding: 'utf8' });
      const вывод = (вышло.stdout || '') + (вышло.stderr || '');
      const итог = /Итого проверок: \d+, провалов: (\d+)/.exec(вывод);
      const покраснела = вышло.status === 1 && !!итог && Number(итог[1]) > 0 && порча.ждём.test(вывод);
      console.log('  порча «' + порча.имя + '»: ' + (покраснела ? 'покраснела' : 'НЕ ПОКРАСНЕЛА'));
      if (!покраснела) console.log(вывод.split('\n').slice(0, 8).join('\n'));
      проверить(покраснела, 'порча «' + порча.имя + '» не покраснела');
    });
  } finally {
    fs.rmSync(папка, { recursive: true, force: true });
  }
}

if (process.argv.indexOf('--сломать') !== -1) {
  сломать();
} else {
  прогнать(довод('--файл') || ФАЙЛ);
}

console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
if (провалов > 0) process.exit(1);
