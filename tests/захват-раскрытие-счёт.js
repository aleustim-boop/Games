// Случай по зерну (Mulberry32): проверка повторяема.
function генератор(зерно) {
  let с = зерно >>> 0;
  return function () {
    с = (с + 0x6D2B79F5) >>> 0;
    let т = с;
    т = Math.imul(т ^ (т >>> 15), т | 1);
    т ^= т + Math.imul(т ^ (т >>> 7), т | 61);
    return ((т ^ (т >>> 14)) >>> 0) / 4294967296;
  };
}

