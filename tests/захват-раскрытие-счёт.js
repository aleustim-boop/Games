// Счёт на начало раскрытия по ТЗ 8.5б п. 1: чужие — войска на начало раунда, свои — плюс поставленное
// минус отправленное (по событиям раунда), области сдавшихся — без хозяина с теми же войсками.
function ждёмНачало(вход) {
  const войска = вход.войскаДо.slice();
  const хозяева = вход.хозяеваДо.slice();
  вход.события.forEach((с) => {
    if (с.вид === 'сдался') хозяева.forEach((х, н) => { if (н > 0 && х === с.кто) хозяева[н] = null; });
    if (с.кто !== вход.я) return;
    if (с.вид === 'расстановка') войска[с.куда] += с.сколько;
    if (с.вид === 'приказ') войска[с.откуда] -= с.сколько;
  });
  return { войска: войска, хозяева: хозяева };
}

// Объясняет ли шаг перемену числа в области н (было → стало). Метка той же величины — в самом шаге.
function объяснено(шаг, н, было, стало, я) {
  const разница = стало - было;
  if (шаг.вид === 'плюс') return шаг.область === н && разница === шаг.сколько;
  if (шаг.вид === 'стрелка') return шаг.откуда === н && шаг.кто !== я && разница === -шаг.сколько;
  if (шаг.вид === 'минус') {
    if (шаг.область !== н) return false;
    if (разница === -шаг.сколько) return true;
    // «Все погибли»: защитники выбиты до нуля, в области остаётся минимум войск (ТЗ 4).
    return было === шаг.сколько && стало === Правила.ЧИСЛА.остаётсяВОбласти;
  }
  // Налив: область была пуста после «−N» защитников, теперь в ней выжившие нападающие.
  if (шаг.вид === 'перекраска') return шаг.область === н && было === 0 && стало > 0;
  return false;
}

// Одно раскрытие с войскаДо: все проверки живого счёта. Отдаёт список найденных бед (пусто — хорошо).
function разобратьСчёт(Р, вход, после, учёт) {
  const беды = [];
  const р = Р.построить(вход);
  const шаги = р.шаги;
  const сСчётом = шаги.filter((ш) => !!ш.счёт);
  if (!сСчётом.length) return ['ни одного шага со счётом'];
  учёт.шаговСоСчётом += сСчётом.length;

  // Шаги по времени и в пределах раскрытия (сдвиг зависимых боёв не выносит их за край).
  for (let и = 1; и < шаги.length; и++) if (шаги[и].с < шаги[и - 1].с) { беды.push('шаги не по времени'); break; }
  if (!шаги.every((ш) => ш.с >= 0 && ш.с + ш.длит <= р.всегоМс)) беды.push('шаг вне 0–' + р.всегоМс + ' мс');

  // Первый снимок — на пластине в нуле, как игрок видел карту перед раскрытием.
  const начало = ждёмНачало(вход);
  const первый = сСчётом[0];
  if (первый.вид !== 'пластина' || первый.с !== 0) беды.push('первый снимок не на пластине в нуле (' + первый.вид + ')');
  if (!равны(первый.счёт.войска, начало.войска)) беды.push('первый снимок: войска не как на начало раскрытия');
  if (!равны(первый.счёт.хозяева, начало.хозяева)) беды.push('первый снимок: хозяева не как на начало раскрытия');
  if (Object.keys(первый.счёт.пилюли).length) беды.push('первый снимок: пилюли до стрелок');

  // Каждая перемена объяснена шагом.
  let прошлый = первый.счёт;
  сСчётом.slice(1).forEach((ш) => {
    const с = ш.счёт;
    с.войска.forEach((стало, н) => {
      const было = прошлый.войска[н];
      if (стало === было) return;
      учёт.перемен++;
      if (!объяснено(ш, н, было, стало, вход.я)) {
        беды.push('область ' + н + ': ' + было + ' → ' + стало + ' на шаге «' + ш.вид + '» без такой метки');
      }
    });
    с.хозяева.forEach((х, н) => {
      if (х === прошлый.хозяева[н]) return;
      if (!(ш.вид === 'перекраска' && ш.область === н && х === ш.на)) беды.push('хозяин области ' + н + ' сменился не наливом (' + ш.вид + ')');
    });
    Object.keys(с.пилюли).forEach((ключ) => {
      if (!(с.пилюли[ключ] > 0)) беды.push('пилюля ' + ключ + ' = ' + с.пилюли[ключ]);
    });
    if (с.войска.some((ч, н) => н > 0 && ч < 0)) беды.push('отрицательное число на шайбе (' + ш.вид + ')');
    прошлый = с;
  });

  // Последний снимок = партия после разбора: на итоговой карте ни одно число не прыгает.
  const последний = сСчётом[сСчётом.length - 1].счёт;
  if (!равны(последний.войска, после.войска)) {
    const где = последний.войска.map((ч, н) => (ч !== после.войска[н] ? н + ':' + ч + '≠' + после.войска[н] : null)).filter(Boolean);
    беды.push('последний снимок: войска не как в партии после разбора (' + где.slice(0, 4).join(', ') + ')');
  }
  if (!равны(последний.хозяева, после.хозяева)) беды.push('последний снимок: хозяева не как в партии после разбора');
  if (Object.keys(последний.пилюли).length) беды.push('после раскрытия остались пилюли ' + JSON.stringify(последний.пилюли));

  // Свои «+N» в доле 0 не повторяются (они в числе с мига касания).
  if (шаги.some((ш) => ш.вид === 'плюс' && ш.кто === вход.я && ш.с < р.фазы[1].с)) беды.push('свой «+N» в доле 0');

  // Пластины ведущего: в начале долей 0, 1 и «бои» (её нет без боёв).
  const пластины = шагиВида(р, 'пластина').map((ш) => [ш.с, ш.строки[0], ш.строки[1]]);
  const заголовок = 'Раунд ' + вход.раунд + ' — раскрытие';
  const ждёмПластины = [[0, заголовок, Р.ВЕДУЩИЙ.пластина], [р.фазы[1].с, заголовок, Р.ВЕДУЩИЙ.стрелки]];
  if (р.боёв > 0) ждёмПластины.push([р.фазы[2].с, заголовок, Р.ВЕДУЩИЙ.бои]);
  if (!равны(пластины, ждёмПластины)) беды.push('пластины ведущего: ' + JSON.stringify(пластины));

  // Причины боёв: без «undefined», не длиннее 36 знаков.
  вход.события.forEach((с) => {
    const причина = Р.причинаБоя(вход, с);
    if (причина === null) return;
    учёт.причин++;
    if (typeof причина !== 'string' || /undefined|NaN|null/.test(причина) || причина.length > ПРИЧИНА_НЕ_ДЛИННЕЕ) {
      беды.push('причина «' + причина + '»');
    }
  });
  if (р.журнал.concat(р.итог).some((с) => /undefined|NaN/.test(с))) беды.push('строка с undefined/NaN');

  // Без войскаДо полей «счёт» нет (запасной путь).
  const безСчёта = Р.построить(Object.assign({}, вход, { войскаДо: undefined }));
  if (безСчёта.шаги.some((ш) => 'счёт' in ш)) беды.push('без войскаДо есть поле «счёт»');

  учёт.пачки += р.боёвВПачке > 1 ? 1 : 0;
  return беды;
}

