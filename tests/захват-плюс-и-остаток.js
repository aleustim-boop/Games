/* =====================================================================
   «Захват»: две правки правил от 03.10 (node, без страницы).

   1. «В плюсе» (ответ владельца «черепаха-очки-не-меньше»): победитель
      из верхней половины стола, кроме первого места, должен закончить
      партию с очками НЕ МЕНЬШЕ, чем было после раздачи. Первое место —
      в плюсе всегда. От этого зависят партия.победители и проигравшие,
      по которым сервер ставит рейтинг.
   2. Остаток подкрепления (ответ владельца «остаток-опасная»): при
      «Готово» и при просрочке несыгранные войска уходят в самую опасную
      свою область (войска врагов по соседству − свои войска в области),
      при равенстве — в свою столицу, дальше меньший номер. Без случая.

   Запуск:  node tests/захват-плюс-и-остаток.js
   Довод:   --правила=<путь>  — взять КОПИЮ игры/захват/захват-правила.js (для
            ломающего запуска). Копия собирается с путём настоящего файла,
            поэтому её require('./захват-карты.js') находит карты.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const Module = require('module');

const ПАПКА_ПРОЕКТА = path.join(__dirname, '..');
const ФАЙЛ_ПРАВИЛ = path.join(ПАПКА_ПРОЕКТА, 'игры', 'захват', 'захват-правила.js');
const Карты = require(path.join(ПАПКА_ПРОЕКТА, 'игры', 'захват', 'захват-карты.js'));

let проверок = 0;
let провалов = 0;
function проверить(условие, слова) {
  проверок++;
  console.log((условие ? '  ок     — ' : '  ПРОВАЛ — ') + слова);
  if (!условие) провалов++;
}

/* Правила: настоящий файл или копия из довода --правила=. */
function загрузитьПравила() {
  const довод = process.argv.find((д) => д.startsWith('--правила='));
  const откуда = довод ? довод.slice('--правила='.length) : ФАЙЛ_ПРАВИЛ;
  if (!fs.existsSync(откуда)) throw new Error('Нет файла правил: ' + откуда);
  const м = new Module(ФАЙЛ_ПРАВИЛ, module);
  м.filename = ФАЙЛ_ПРАВИЛ;
  м.paths = Module._nodeModulePaths(path.dirname(ФАЙЛ_ПРАВИЛ));
  м._compile(fs.readFileSync(откуда, 'utf8'), ФАЙЛ_ПРАВИЛ);
  if (довод) console.log('Правила взяты из копии: ' + откуда);
  return м.exports;
}
const П = загрузитьПравила();

/* Материк на 4 места: столицы B(2), G(7), O(15), Q(17), по 4 области на старте. */
function партияМатерик() {
  return П.новаяПартия({
    игроки: ['X', 'Y', 'Z', 'W'],
    столицы: { X: 'B', Y: 'G', Z: 'O', W: 'Q' },
    порядок: ['X', 'Y', 'Z', 'W'],
    областейНаСтарте: 4,
    карта: 'материк'
  }, () => 0);
}

/* Владения руками: остальные области ничьи. войска — {номер: сколько}. */
function задатьВладения(партия, владения, войска) {
  for (let н = 1; н < партия.хозяева.length; н++) партия.хозяева[н] = null;
  Object.keys(владения).forEach((к) => владения[к].forEach((н) => { партия.хозяева[н] = к; }));
  Object.keys(войска || {}).forEach((н) => { партия.войска[Number(н)] = войска[н]; });
  return партия;
}

/* ---------- Задача 1: кто «в плюсе» ---------- */

/* Последний раунд без приказов и подкрепления: партия кончается «по раундам»,
   итог пишут сами правила (закончить). Отдаёт партию после разбора. */
function доиграть(партия) {
  партия.игроки.forEach((к) => { партия.подкрепление[к] = 0; });
  партия.раунд = партия.всегоРаундов;
  return П.разобратьРаунд(партия, {}, () => 0.99).партия;
}

function показ(п) {
  return 'места ' + (п.итог ? п.итог.места.map((м) => м.кто + ':' + м.очки).join(' ') : '—') +
    ', победители ' + JSON.stringify(п.победители) + ', проигравшие ' + JSON.stringify(п.проигравшие);
}

function задача1() {
  console.log('Задача 1: «в плюсе» — очков не меньше, чем на старте');
  const старт = партияМатерик();
  const ждёмНаСтарте = {};
  старт.игроки.forEach((к) => { ждёмНаСтарте[к] = П.очки(старт, к); });
  проверить(!!старт.очкиНаСтарте && JSON.stringify(старт.очкиНаСтарте) === JSON.stringify(ждёмНаСтарте) &&
    старт.игроки.every((к) => старт.очкиНаСтарте[к] === 7),
    'новая партия помнит очки после раздачи: у всех по 7 (4 области + столица) — ' + JSON.stringify(старт.очкиНаСтарте));

  // а) Второе место (верхняя половина из 4) потеряло очки: 3 против 7 на старте — не в плюсе.
  const а = доиграть(задатьВладения(партияМатерик(), { X: [1, 2, 3, 4, 5, 6, 8, 9, 10], Y: [11, 12, 13], Z: [14], W: [16] }));
  проверить(а.завершена === true && а.итог.места[1].кто === 'Y' && а.итог.места[1].очки === 3,
    'а) партия кончилась, Y на 2-м месте с 3 очками (ноль — провал) — ' + показ(а));
  проверить(JSON.stringify(а.победители) === '["X"]' && а.проигравшие.indexOf('Y') !== -1,
    'а) 2-е место с потерей очков не в плюсе: победитель только X, Y в проигравших — ' + показ(а));
  проверить(JSON.stringify(а.итог.победители) === '["X"]',
    'а) экран итога получает тех же победителей — ' + JSON.stringify(а.итог.победители));

  // б) Второе место ровно с теми же очками, что на старте: 7 — в плюсе.
  const б = доиграть(задатьВладения(партияМатерик(), { X: [1, 2, 3, 4, 5, 6, 8, 9, 10], Y: [7, 11, 12, 13], Z: [14], W: [16] }));
  проверить(б.итог.места[1].кто === 'Y' && б.итог.места[1].очки === 7,
    'б) Y на 2-м месте с 7 очками, как на старте (ноль — провал) — ' + показ(б));
  проверить(JSON.stringify(б.победители) === '["X","Y"]' && б.проигравшие.indexOf('Y') === -1,
    'б) очков столько же, сколько на старте, — в плюсе: победители X и Y — ' + показ(б));

  // в) Первое место тоже потеряло очки (3 против 7) — всё равно в плюсе; второе с потерей — нет.
  const в = доиграть(задатьВладения(партияМатерик(), { X: [1, 3, 4], Y: [11, 12], Z: [14], W: [16] }));
  проверить(в.итог.места[0].кто === 'X' && в.итог.места[0].очки === 3 && в.итог.места[1].кто === 'Y',
    'в) X на 1-м месте с 3 очками, Y на 2-м (ноль — провал) — ' + показ(в));
  проверить(JSON.stringify(в.победители) === '["X"]' && в.результат === 'X',
    'в) первое место в плюсе даже с потерей, второе с потерей — нет — ' + показ(в));

  // в2) Старт был неравный (так бывает, когда при раздаче кому-то не хватило областей): X начинал с 20,
  //     кончил 1-м с 12 — в плюсе; Y сохранил свои 7 — тоже. Без правила «первое всегда» X выпал бы,
  //     а запасное «место 1» не спасло бы его, потому что Y в списке остаётся.
  const неравный = задатьВладения(партияМатерик(), { X: [1, 2, 3, 4, 5, 6, 8, 9, 10], Y: [7, 11, 12, 13], Z: [14], W: [16] });
  неравный.очкиНаСтарте.X = 20;
  const в2 = доиграть(неравный);
  проверить(в2.итог.места[0].кто === 'X' && в2.итог.места[0].очки === 12 && в2.итог.места[1].очки === 7,
    'в2) X 1-й с 12 при 20 на старте, Y 2-й с 7 (ноль — провал) — ' + показ(в2));
  проверить(JSON.stringify(в2.победители) === '["X","Y"]',
    'в2) первое место в плюсе при потере, даже когда второе в плюсе само — ' + показ(в2));

  // г) Партия из старого сохранения без очкиНаСтарте — как раньше: верхняя половина живых.
  const старая = задатьВладения(партияМатерик(), { X: [1, 2, 3, 4, 5, 6, 8, 9, 10], Y: [11, 12, 13], Z: [14], W: [16] });
  delete старая.очкиНаСтарте;
  const г = доиграть(старая);
  проверить(JSON.stringify(г.победители) === '["X","Y"]',
    'г) старое сохранение без очков на старте не падает и считается по-старому — ' + показ(г));
}

/* ---------- Задача 2: куда уходит остаток ---------- */

function соседи(номер) {
  return Карты.соседство(Карты.КАРТЫ.материк)[номер] || [];
}

function задача2() {
  console.log('Задача 2: остаток — в самую опасную свою область');
  // Заготовки держатся на соседстве материка: сверяем его с картой, а не верим на слово.
  const нужноеСоседство = соседи(4).indexOf(10) !== -1 && соседи(10).indexOf(4) !== -1 &&
    [1, 2, 3].every((н) => соседи(н).indexOf(10) === -1) &&
    соседи(3).indexOf(11) !== -1 && соседи(4).indexOf(11) === -1 &&
    соседи(6).indexOf(8) !== -1 && соседи(7).indexOf(8) !== -1 && соседи(4).indexOf(1) !== -1;
  проверить(нужноеСоседство, 'соседство материка такое, на каком собраны заготовки (4–10, 3–11, 6–8, 7–8, 4–1)');

  // а) Своя столица B(2) в тылу, на Утёс(4) смотрит Брод(10) Y с 9 войсками — остаток в Утёс.
  const а = задатьВладения(партияМатерик(), { X: [1, 2, 3, 4], Y: [10] }, { 1: 2, 2: 4, 3: 2, 4: 3, 10: 9 });
  а.подкрепление.X = 5;
  const черновикА = { расстановка: { 1: 1 }, приказы: [] };
  const доА = JSON.stringify(черновикА);
  const итогА = П.остатокПоПросрочке(а, 'X', черновикА);
  проверить(JSON.stringify(итогА.расстановка) === '{"1":1,"4":4}',
    'а) опасная область — не столица: остаток 4 ушёл в Утёс(4), не в столицу B(2) — ' + JSON.stringify(итогА.расстановка));
  проверить(JSON.stringify(П.кудаОстаток(а, 'X', черновикА)) === '{"область":4,"столица":false}',
    'а) кудаОстаток (по нему спрашивает браузер) называет ту же область 4, не столицу — ' + JSON.stringify(П.кудаОстаток(а, 'X', черновикА)));
  проверить(JSON.stringify(черновикА) === доА, 'а) присланный черновик не изменён');
  проверить(П.проверитьЧерновик(а, 'X', итогА).принято === true, 'а) черновик с остатком проходит проверку');

  // б) Равная опасность: Маяк(6) и столица Фьорд(7) у Y, обе рядом с Торосом(8) X (5 войск), по 2 своих.
  //    Опасность 5 − 2 = 3 у обеих — остаток в столицу 7, хотя у Маяка номер меньше.
  const б = задатьВладения(партияМатерик(), { Y: [6, 7], X: [8] }, { 6: 2, 7: 2, 8: 5 });
  б.подкрепление.Y = 3;
  const итогБ = П.остатокПоПросрочке(б, 'Y', { расстановка: {}, приказы: [] });
  проверить(JSON.stringify(итогБ.расстановка) === '{"7":3}',
    'б) равная опасность — остаток в свою столицу Фьорд(7) — ' + JSON.stringify(итогБ.расстановка));
  проверить(JSON.stringify(П.кудаОстаток(б, 'Y', {})) === '{"область":7,"столица":true}',
    'б) кудаОстаток помечает выбор как столицу — ' + JSON.stringify(П.кудаОстаток(б, 'Y', {})));

  // в) Свои войска — после черновика: Перевал(3) и Утёс(4) по 4, рядом по 6 врага — поровну, меньший номер 3.
  //    Приказ уводит 2 из Утёса — он становится опаснее, остаток туда.
  const в = задатьВладения(партияМатерик(), { X: [3, 4], Y: [10, 11] }, { 3: 4, 4: 4, 10: 6, 11: 6 });
  в.подкрепление.X = 3;
  const безПриказа = П.остатокПоПросрочке(в, 'X', { расстановка: {}, приказы: [] });
  проверить(JSON.stringify(безПриказа.расстановка) === '{"3":3}',
    'в) поровну и столицы нет — меньший номер, Перевал(3) — ' + JSON.stringify(безПриказа.расстановка));
  const сПриказом = П.остатокПоПросрочке(в, 'X', { расстановка: {}, приказы: [{ из: 4, в: 1, сколько: 2 }] });
  проверить(JSON.stringify(сПриказом.расстановка) === '{"4":3}',
    'в) приказ увёл 2 из Утёса(4) — он опаснее, остаток туда — ' + JSON.stringify(сПриказом.расстановка));

  // д) Угрожаемая область с отрицательной опасностью всё равно выше тыла без врагов: в Утёсе(4) 6 своих,
  //    рядом Брод(10) Y с 2 (опасность −4); Пик(1) в тылу (опасность 0, врагов рядом нет). Столица B ничья.
  const д = задатьВладения(партияМатерик(), { X: [1, 4], Y: [10] }, { 1: 2, 4: 6, 10: 2 });
  д.подкрепление.X = 3;
  const итогД = П.остатокПоПросрочке(д, 'X', { расстановка: {}, приказы: [] });
  проверить(JSON.stringify(итогД.расстановка) === '{"4":3}',
    'д) угрожаемая с опасностью −4 выше тыла с 0: остаток в Утёс(4), не в Пик(1) — ' + JSON.stringify(итогД.расстановка));

  // е) Ничья область не враг: рядом с Перевалом(3) ничья область 11 с 50 войсками, рядом с Утёсом(4)
  //    Брод(10) Y с 5. Опасность Утёса 5 − 3 = 2, Перевалу никто не угрожает — остаток в Утёс.
  const е = задатьВладения(партияМатерик(), { X: [3, 4], Y: [10] }, { 3: 3, 4: 3, 10: 5, 11: 50 });
  е.подкрепление.X = 3;
  const итогЕ = П.остатокПоПросрочке(е, 'X', { расстановка: {}, приказы: [] });
  проверить(е.хозяева[11] === null && JSON.stringify(итогЕ.расстановка) === '{"4":3}',
    'е) ничья область с 50 войсками рядом не в счёт: остаток в Утёс(4), не в Перевал(3) — ' + JSON.stringify(итогЕ.расстановка));

  // ж) Врагов рядом нет ни у одной области: у Y Маяк(6) с 1 и столица Фьорд(7) с 9, соседи 8 и 9 ничьи.
  //    Все без угрозы — остаток в столицу 7, хотя у Маяка номер меньше и своих войск меньше.
  const ж = задатьВладения(партияМатерик(), { Y: [6, 7] }, { 6: 1, 7: 9 });
  ж.подкрепление.Y = 3;
  const итогЖ = П.остатокПоПросрочке(ж, 'Y', { расстановка: {}, приказы: [] });
  проверить(JSON.stringify(итогЖ.расстановка) === '{"7":3}',
    'ж) врагов рядом нет нигде — остаток в свою столицу Фьорд(7), не в Маяк(6) — ' + JSON.stringify(итогЖ.расстановка));

  // г) Повтор и JSON-круг дают то же самое (браузер и сервер получают партию через JSON).
  const снова = П.остатокПоПросрочке(JSON.parse(JSON.stringify(а)), 'X', JSON.parse(доА));
  const ещё = П.остатокПоПросрочке(а, 'X', JSON.parse(доА));
  проверить(JSON.stringify(снова) === JSON.stringify(итогА) && JSON.stringify(ещё) === JSON.stringify(итогА),
    'г) повтор и копия через JSON дают тот же остаток — ' + JSON.stringify(снова.расстановка));
}

try {
  задача1();
  задача2();
} catch (ошибка) {
  провалов++;
  console.log('  ПРОВАЛ — проверка упала: ' + (ошибка && ошибка.stack || ошибка));
}
console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
process.exit(провалов ? 1 : 0);
