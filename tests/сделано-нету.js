/*
  Проверка для штаб/сделано.js: поле «нету» в примете (зеркало «есть»).

  Зачем. Примета умела вычёркивать дело, только если в опубликованном файле
  строка ПОЯВИЛАСЬ. Задачи вида «убрать кнопку», «удалить экран» на такой
  примете закрыть было нельзя в принципе. Сегодня на это наткнулись на
  «убрать Раздачу дня из лобби»: работа сделана и опубликована (коммит
  7563f73), а вычеркнуть было нечем.

  Проверка читает НАСТОЯЩИЙ опубликованный index.html (origin/main) — ту же
  сущность, с которой работает сама программа, вторых копий чисел тут нет.
  Файлы игры проверка не трогает, только читает.

    node tests/сделано-нету.js            — обычный прогон.
    node tests/сделано-нету.js --сломать  — ломающий: примета с «нету» на
      строку, которая в опубликованном ТОЧНО есть («экран-лобби» — часть
      разметки лобби, её не убирали). Если бы «нету» отвечало «сделано» на
      всё подряд (перепутали направление сравнения) — тест покраснел бы.
*/

const { spawnSync } = require('child_process');
const path = require('path');

const корень = path.join(__dirname, '..');
const { следВКоде } = require(path.join(корень, 'штаб', 'сделано.js'));

const сломать = process.argv.includes('--сломать');

let проверок = 0;
const провалы = [];

function проверить(условие, что) {
  проверок++;
  if (!условие) {
    провалы.push(что);
    console.log('  ПРОВАЛ: ' + что);
  }
}

/* Без origin/main сверять нечего — программа сама в этом случае молчит,
   и проверка честно поступает так же: не выдаёт ни зелёного, ни красного. */
const публикацияВидна = spawnSync('git', ['rev-parse', '--verify', 'origin/main'],
  { cwd: корень, windowsHide: true });
if (публикацияВидна.error || публикацияВидна.status !== 0) {
  console.log('origin/main не виден на этой машине — проверять не с чем, выходим без оценки.');
  process.exit(0);
}

if (!сломать) {
  // 1. Строку «кнопка-раздача-дня» из index.html убрали и опубликовали
  //    (коммит 7563f73). Примета «нету» обязана признать дело сделанным.
  const убралиРаздачуДня = следВКоде({ файл: 'index.html', нету: 'кнопка-раздача-дня' });
  проверить(
    !!убралиРаздачуДня && убралиРаздачуДня.нашлось === true,
    '«нету: кнопка-раздача-дня» не признала сделанным дело, которое реально сделано и опубликовано'
  );
  проверить(
    !!убралиРаздачуДня && убралиРаздачуДня.чем.indexOf('больше нет') !== -1,
    'пояснение для сработавшей «нету» не объясняет по-русски, что строки больше нет'
  );

  // 2. Оба поля разом, оба верны: строка «экран-лобби» в разметке есть,
  //    строки «кнопка-раздача-дня» уже нет. Дело должно считаться сделанным.
  const обаВерны = следВКоде({ файл: 'index.html', есть: 'экран-лобби', нету: 'кнопка-раздача-дня' });
  проверить(
    !!обаВерны && обаВерны.нашлось === true,
    'при верных «есть» и «нету» одновременно примета не признала дело сделанным'
  );

  // 3. Оба поля разом, но перепутаны местами: «есть» ищет то, чего нет,
  //    «нету» проверяет то, что ещё есть. Ни одно условие не сошлось —
  //    дело не должно засчитаться по одному лишь совпавшему полю.
  const обаНеВерны = следВКоде({ файл: 'index.html', есть: 'кнопка-раздача-дня', нету: 'экран-лобби' });
  проверить(
    !!обаНеВерны && обаНеВерны.нашлось === false,
    'при перепутанных «есть» и «нету» примета всё равно посчитала дело сделанным'
  );
} else {
  // Ломающий прогон: «экран-лобби» в опубликованном index.html точно есть
  // (это часть каркаса лобби дурака, её не убирали). Примета с «нету» на
  // такую строку обязана честно ответить «не сделано».
  const строкаЕщёЕсть = следВКоде({ файл: 'index.html', нету: 'экран-лобби' });
  проверить(
    !!строкаЕщёЕсть && строкаЕщёЕсть.нашлось === false,
    '«нету: экран-лобби» посчитала дело сделанным, хотя строка в опубликованном всё ещё есть'
  );
  проверить(
    !!строкаЕщёЕсть && строкаЕщёЕсть.чем.indexOf('всё ещё есть') !== -1,
    'пояснение при несработавшей «нету» не говорит по-русски, что строка всё ещё на месте'
  );
}

console.log('Итого проверок: ' + проверок + ', провалов: ' + провалы.length);
process.exit(провалы.length > 0 ? 1 : 0);
