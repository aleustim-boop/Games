'use strict';

/* =====================================================================
   «ЗАХВАТ»: ЛАТИНСКОЕ ИМЯ В общее/js/telegram.js — этап Б1.

   Зачем. Рекорды и рейтинг игры лежат под ключом с латинским именем игры
   («records_zahvat»). Не впишут «захват» в ЛАТИНСКОЕ_ИМЯ_ИГРЫ — ключ
   соберётся из числа («records_1234»), а в день, когда имя допишут, ключ
   сменится, и накопленные рекорды пропадут для человека молча.

   Что проверяем:
     1. в списке ЛАТИНСКОЕ_ИМЯ_ИГРЫ строка 'захват' ведёт ровно на 'zahvat';
     2. на деле: поднимаем общее/js/telegram.js в поддельном браузере, пишем рекорд
        и читаем рейтинг игры «захват» — ключи, под которыми файл полез
        в память и в облако, ровно records_zahvat и rating_zahvat: без
        кириллицы и не «имя_число».

   Запуск:  node tests/захват-имя-игры.js [--файл <путь к копии telegram.js>]
   Порча:   node tests/захват-имя-игры.js --сломать
            (две порченые копии во временной папке; проверка обязана
             покраснеть на обеих; файл проекта не трогаем)
   Выход 0 — провалов нет.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');
const { поднятьTelegramJS, сделатьОблако, КОРЕНЬ } = require('./поддельный-браузер.js');

const аргументы = process.argv.slice(2);
const номерФайла = аргументы.indexOf('--файл');
const путьКФайлу = номерФайла !== -1 && аргументы[номерФайла + 1]
  ? path.resolve(аргументы[номерФайла + 1])
  : path.join(КОРЕНЬ, 'общее', 'js', 'telegram.js');

let проверок = 0;
let провалов = 0;
function проверить(условие, что) {
  проверок++;
  if (!условие) { провалов++; console.log('  ПРОВАЛ: ' + что); }
  else console.log('  ок   ' + что);
}

/* ---------------------------------------------------------------------
   Порча: две копии во временной папке, каждая обязана провалить проверку
   --------------------------------------------------------------------- */

function сломать() {
  const исходник = fs.readFileSync(путьКФайлу, 'utf8');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-имя-'));
  const порчи = [
    { имя: 'строка «захват» убрана', текст: исходник.replace(/^\s*'захват'\s*:\s*'zahvat',?\s*$/m, '') },
    { имя: '«zahvat» заменено на «zahvat2»', текст: исходник.replace("'zahvat'", "'zahvat2'") }
  ];
  let несработало = 0;
  for (const порча of порчи) {
    if (порча.текст === исходник) {
      console.log('  ПРОВАЛ порчи «' + порча.имя + '»: в файле нечего портить — порча ничего не изменила');
      несработало++;
      continue;
    }
    const копия = path.join(папка, 'telegram.js');
    fs.writeFileSync(копия, порча.текст, 'utf8');
    let код = 0;
    try {
      execFileSync(process.execPath, [__filename, '--файл', копия], { stdio: 'pipe' });
    } catch (ошибка) {
      код = ошибка.status || 1;
    }
    if (код === 0) {
      console.log('  ПРОВАЛ порчи «' + порча.имя + '»: проверка осталась зелёной');
      несработало++;
    } else {
      console.log('  ок   порча «' + порча.имя + '» покрасила проверку (выход ' + код + ')');
    }
  }
  fs.rmSync(папка, { recursive: true, force: true });
  console.log('Итого порч: ' + порчи.length + ', не покраснело: ' + несработало);
  process.exit(несработало ? 1 : 0);
}

if (аргументы.indexOf('--сломать') !== -1) сломать();

/* ---------------------------------------------------------------------
   1. Список имён в тексте файла
   --------------------------------------------------------------------- */

const исходник = fs.readFileSync(путьКФайлу, 'utf8');
const кусокСписка = исходник.match(/ЛАТИНСКОЕ_ИМЯ_ИГРЫ\s*=\s*\{([\s\S]*?)\}/);
проверить(кусокСписка !== null, 'в файле нашёлся список ЛАТИНСКОЕ_ИМЯ_ИГРЫ');
const имена = {};
if (кусокСписка) {
  for (const пара of (кусокСписка[1].match(/'([^']+)'\s*:\s*'([^']+)'/g) || [])) {
    const р = пара.match(/'([^']+)'\s*:\s*'([^']+)'/);
    имена[р[1]] = р[2];
  }
}
проверить(Object.keys(имена).length > 0, 'в списке нашлись пары (ноль найденного — провал)');
проверить(имена['захват'] === 'zahvat', 'в списке «захват» ведёт ровно на «zahvat» (сейчас: ' + имена['захват'] + ')');

/* ---------------------------------------------------------------------
   2. На деле: какие ключи строит файл для игры «захват»
   --------------------------------------------------------------------- */

async function накормить() {
  const облако = сделатьОблако({});
  const спрошенные = [];
  const прежнийGet = облако.getItem;
  облако.getItem = function (ключ, ответить) { спрошенные.push(ключ); return прежнийGet(ключ, ответить); };

  const стенд = поднятьTelegramJS({ исходник: исходник, облако: облако });
  await стенд.окно.saveScore(7, 'лёгкая', 'захват');
  await стенд.окно.Рейтинг.прочитать('захват');
  await new Promise(function (готово) { setTimeout(готово, 20); });

  const ключи = new Set(стенд.память.ключи());
  for (const к of Object.keys(облако.ящик)) ключи.add(к);
  for (const к of спрошенные) ключи.add(к);
  return Array.from(ключи);
}

накормить().then(function (ключи) {
  const рекордные = ключи.filter(к => к.indexOf('records_') === 0);
  const рейтинговые = ключи.filter(к => к.indexOf('rating_') === 0);
  проверить(рекордные.length >= 1, 'файл строит ключ рекордов для «захват» (нашлось ' + рекордные.length + ')');
  проверить(рейтинговые.length >= 1, 'файл строит ключ рейтинга для «захват» (нашлось ' + рейтинговые.length + ')');
  проверить(рекордные.length + рейтинговые.length > 0 && ключи.every(к => /^[A-Za-z0-9_-]+$/.test(к)),
    'в ключах нет кириллицы и лишних знаков: ' + ключи.join(', '));
  for (const ключ of рекордные.concat(рейтинговые)) {
    проверить(ключ.indexOf('zahvat') !== -1, 'ключ «' + ключ + '» содержит zahvat');
    проверить(!/_\d+$/.test(ключ), 'ключ «' + ключ + '» не вида «имя_число»');
  }
  проверить(ключи.indexOf('records_zahvat') !== -1, 'есть ровно records_zahvat');
  проверить(ключи.indexOf('rating_zahvat') !== -1, 'есть ровно rating_zahvat');

  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
}).catch(function (ошибка) {
  console.log('  ПРОВАЛ: стенд упал: ' + (ошибка && ошибка.stack || ошибка));
  console.log('Итого проверок: ' + (проверок + 1) + ', провалов: ' + (провалов + 1));
  process.exit(1);
});
