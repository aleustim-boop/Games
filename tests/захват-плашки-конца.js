// Опытный игрок: подсказки новичка выключены, пилюля свободна для плашек.
const ботыСВыбором = (длина, ещё) => Object.assign({ 'zahvat-learned': '1' },
  { 'zahvat-bots': JSON.stringify({ мест: 3, уровень: 'лёгкий', раундовЗахвата: длина }) }, ещё || {});

function сыгратьРаунд(м) {
  м.готово();
  const п = м.построения[м.построения.length - 1];
  if (п) м.таймеры.прошло(п.расписание.всегоМс);
}

/** Живая партия с ботами: что показывала пилюля в начале каждого раунда. Возвращает { раунд: [слова на старте] }. */
async function сыгратьПартиюИСобратьПлашки(длина) {
  const м = мирБотов(ботыСВыбором(длина), 7);
  м.нажать('захват-боты');
  м.нажать('захват-начать');
  await дождатьсяКартинок();
  const увидено = {};
  const записать = () => {
    const н = м.раунд();
    if (н === null) return;
    (увидено[н] = увидено[н] || []).push(м.плашка());
  };
  for (let шаг = 0; шаг < 60; шаг++) {
    записать();
    const раундДо = м.раунд();
    сыгратьРаунд(м);
    if (м.раунд() === раундДо) break;   // раунд не сменился: партия кончилась
  }
  return { увидено, м };
}

/** Мир, продолженный с сохранения, где партия «перемотана» на раунд; ещё — доп. поля сохранения (для повторного открытия). */
async function мирНаРаунде(длина, раунд, сохранениеДляПродолжения) {
  let сохр = сохранениеДляПродолжения;
  if (!сохр) {
    const м0 = мирБотов(ботыСВыбором(длина), 7);
    м0.нажать('захват-боты');
    м0.нажать('захват-начать');
    await дождатьсяКартинок();
    сыгратьРаунд(м0);
    сохр = м0.сохранение();
    сохр.партия.раунд = раунд;
    delete сохр.плашкиКонца;
  }
  const м = мирБотов(ботыСВыбором(длина, { 'zahvat-save': JSON.stringify(сохр) }), 11);
  м.нажать('захват-продолжить');
  await дождатьсяКартинок();
  return м;
}

function ожидаемаяПлашка(длина, раунд) {
  if (длина === 'победа') return '';
  if (раунд === длина - 2) return ТЕКСТ_ТРИ;
  if (раунд === длина) return ТЕКСТ_ПОСЛЕДНИЙ;
  return '';
}

async function проверитьБотов() {
  // 1. Каждый раунд каждой длины: плашка ровно там, где положено (ноль показанных — провал).
  for (const длина of [10, 15, 20, 'победа']) {
    let показано = 0, ошибки = [];
    const раунды = [];
    for (let р = 1; р <= (длина === 'победа' ? 50 : длина); р++) раунды.push(р);
    for (const р of раунды) {
      // Для «До победы» берём только раунды вокруг чисел 10/15/20 и их N−2, остальные те же по смыслу.
      if (длина === 'победа' && ![8, 10, 13, 15, 18, 20, 48, 50].includes(р)) continue;
      const м = await мирНаРаунде(длина, р);
      const есть = м.плашка();
      if (есть) показано++;
      if (есть !== ожидаемаяПлашка(длина, р)) ошибки.push('раунд ' + р + ': «' + есть + '»');
      if (м.ошибки.length) ошибки.push('консоль: ' + м.ошибки.join(' | '));
    }
    проверка('боты, ' + длина + ': плашки только на своих раундах', ошибки.length === 0, ошибки.join('; '));
    if (длина !== 'победа') проверка('боты, ' + длина + ': плашка показалась ровно дважды (ноль — провал)', показано === 2, 'показано ' + показано);
    else проверка('боты, «До победы»: плашек нет совсем', показано === 0, 'показано ' + показано);
  }

  // 2. Одна живая партия: за каждый раунд пилюля со словами плашки стоит на старте ровно один раз.
  for (const длина of [10, 15, 20]) {
    const { увидено, м } = await сыгратьПартиюИСобратьПлашки(длина);
    const раунды = Object.keys(увидено).map(Number);
    проверка('боты, живая партия на ' + длина + ': дошли до раунда N−2 (ноль — провал)', раунды.includes(длина - 2), 'раунды ' + раунды.join(','));
    const лишние = раунды.filter(р => увидено[р].length !== 1 || увидено[р][0] !== ожидаемаяПлашка(длина, р));
    проверка('боты, живая партия на ' + длина + ': на старте раунда ровно то, что положено',
      лишние.length === 0, лишние.map(р => р + ': ' + JSON.stringify(увидено[р])).join('; '));
    проверка('боты, живая партия на ' + длина + ': плашка N−2 стояла', раунды.includes(длина - 2) && увидено[длина - 2][0] === ТЕКСТ_ТРИ);
    проверка('боты, живая партия на ' + длина + ': консоль чистая', м.ошибки.length === 0, м.ошибки.join(' | '));
  }

  // 3. «Продолжить» в раунде N−2 после показа плашки: второй раз не показывает.
  for (const длина of [10, 15, 20]) {
    const первый = await мирНаРаунде(длина, длина - 2);
    проверка('боты, ' + длина + ': первое открытие раунда N−2 показало плашку (ноль — провал)', первый.плашка() === ТЕКСТ_ТРИ, первый.плашка());
    const сохр = первый.сохранение();
    проверка('боты, ' + длина + ': отметка «плашка была» легла в сохранение', Array.isArray(сохр.плашкиКонца) && сохр.плашкиКонца.includes(длина - 2), JSON.stringify(сохр.плашкиКонца));
    const второй = await мирНаРаунде(длина, длина - 2, сохр);
    проверка('боты, ' + длина + ': повторное открытие того же раунда плашку не повторяет', второй.плашка() === '', второй.плашка());
  }
}

