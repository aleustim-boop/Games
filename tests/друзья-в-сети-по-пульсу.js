let ПОРТ = 0;   // узнаём фактический порт после listen(0, ...)

/** Тела ответов именно /пульс — под конец проверяем на утечку номеров. */
const телаПульса = [];

function сырое(путь, телоСтрокой) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(телоСтрокой, 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН_АДРЕС, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (сбой) { разобрано = null; }
        if (путь === '/пульс') телаПульса.push(текст);
        готово({ код: ответ.statusCode, тело: разобрано, текст: текст });
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

function спросить(путь, тело) {
  return сырое(путь, JSON.stringify(тело === undefined ? {} : тело));
}

/** Подписанный запрос от имени игрока. */
function дверь(путь, кто, имя, довесок) {
  const тело = Object.assign({ initData: подписьИгрока(кто, имя) }, довесок || {});
  return спросить(путь, тело);
}

/** Найти запись друга в /друзья-онлайн по ключу — а не по имени: у
    друга, который ни разу не прислал подписанный пульс, имя пустое,
    и поиск по имени тихо не нашёл бы его вовсе (провал, а не пропуск). */
function найтиПоКлючу(список, кто, номерДруга) {
  const ключ = сервера.ключДруга(кто, номерДруга);
  return (список || []).find(function (запись) { return запись.ключ === ключ; });
}

