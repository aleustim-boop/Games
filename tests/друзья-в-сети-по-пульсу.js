function проверитьУтечкиПульса() {
  console.log('5. Ни в одном ответе /пульс нет длинных чисел, похожих на номер Telegram');
  let номеровНайдено = 0;
  телаПульса.forEach(function (текст, к) {
    if (/\d{6,}/.test(текст)) {
      номеровНайдено++;
      console.log('  подробности утечки в ответе /пульс №' + к + ': ' + текст.slice(0, 300));
    }
  });
  проверить(номеровНайдено === 0,
    'ни в одном из ' + телаПульса.length + ' собранных ответов /пульс нет длинных чисел — а нашлись в ' + номеровНайдено);
}

