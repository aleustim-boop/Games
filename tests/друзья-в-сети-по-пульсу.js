/**
 * Вырезать строку «присутствие.отметить(...)» из функции принятьПульс
 * в указанном файле сервер.js. Строки для порчи нет — это уже сама по
 * себе провальная поломка: дальше пробовать нечего, выходим сразу.
 */
function испортитьКопиюСервера(путьКФайлу) {
  const текст = fs.readFileSync(путьКФайлу, 'utf8');
  const маркерНачала = 'function принятьПульс(тело, ответ) {';
  const начало = текст.indexOf(маркерНачала);
  if (начало === -1) {
    throw new Error('в копии не нашлась функция принятьПульс — портить нечего');
  }
  // Файл может лежать с CRLF (\r\n) — маркер конца функции подбираем
  // под тот же перевод строки, что реально использован в файле.
  const ПС = текст.indexOf('\r\n') !== -1 ? '\r\n' : '\n';
  const конец = текст.indexOf(ПС + '}' + ПС, начало);
  if (конец === -1) {
    throw new Error('в копии не нашёлся конец функции принятьПульс — портить нечего');
  }
  const кусок = текст.slice(начало, конец);
  const идxСтроки = кусок.indexOf('присутствие.отметить(');
  if (идxСтроки === -1) {
    throw new Error('строка «присутствие.отметить» внутри принятьПульс не нашлась — портить нечего');
  }
  const началоСтроки = кусок.lastIndexOf('\n', идxСтроки) + 1;
  const концаСтрокиОтступ = кусок.indexOf('\n', идxСтроки);
  const концаСтроки = концаСтрокиОтступ === -1 ? кусок.length : концаСтрокиОтступ + 1;
  const испорченныйКусок = кусок.slice(0, началоСтроки) + кусок.slice(концаСтроки);
  const новыйТекст = текст.slice(0, начало) + испорченныйКусок + текст.slice(конец);
  fs.writeFileSync(путьКФайлу, новыйТекст, 'utf8');
}

/**
 * Подготовить временную копию server/ и js/ с испорченной строкой,
 * вернуть путь к её корню. Копию делает и портит САМА эта проверка —
 * настоящий проект она не трогает вовсе. Порча не удалась (строки для
 * порчи не нашлось) — временную папку сразу убираем и выходим: копия
 * без поломки никого бы не обманула.
 */
function приготовитьИспорченнуюКопию() {
  const временная = fs.mkdtempSync(path.join(os.tmpdir(), 'друзья-в-сети-по-пульсу-сломать-'));
  try {
    fs.cpSync(path.join(КОРЕНЬ_ПРОЕКТА, 'server'), path.join(временная, 'server'), { recursive: true });
    require('./пути-проекта.js').скопироватьКод(КОРЕНЬ_ПРОЕКТА, временная, 'js');
    испортитьКопиюСервера(path.join(временная, 'server', 'сервер.js'));
  } catch (беда) {
    console.error('ЛОМАЮЩИЙ ЗАПУСК: ' + беда.message + ' — сразу провал');
    try { fs.rmSync(временная, { recursive: true, force: true }); } catch (е) { /* не критично */ }
    process.exit(1);
  }
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: проверяем испорченную копию в ' + временная + ' ***');
  return временная;
}

