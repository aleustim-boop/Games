/** В СТРАНИЦЕ: общие замеры узла по id. Не найден — { есть: false }. */
function замерить(идЫ) {
  const W = document.documentElement.clientWidth, H = window.innerHeight;
  const итог = { W: W, H: H, узлы: {} };
  const видно = function (у) {
    const р = у.getBoundingClientRect(), с = getComputedStyle(у);
    return с.display !== 'none' && с.visibility !== 'hidden' && р.width > 0 && р.height > 0 && !у.closest('.скрыт');
  };
  идЫ.forEach(function (id) {
    const у = document.getElementById(id);
    if (!у) { итог.узлы[id] = { есть: false }; return; }
    const р = у.getBoundingClientRect();
    const диалог = у.closest('dialog');
    const д = диалог ? диалог.getBoundingClientRect() : null;
    const ц = document.elementFromPoint((р.left + р.right) / 2, (р.top + р.bottom) / 2);
    итог.узлы[id] = {
      есть: true, виден: видно(у), текст: у.textContent.trim(),
      x: р.left, y: р.top, r: р.right, b: р.bottom, w: р.width, h: р.height,
      вЭкране: р.left >= -0.5 && р.top >= -0.5 && р.right <= W + 0.5 && р.bottom <= H + 0.5,
      вДиалоге: Boolean(д) && р.left >= д.left - 0.5 && р.top >= д.top - 0.5 && р.right <= д.right + 0.5 && р.bottom <= д.bottom + 0.5,
      диалогЕсть: Boolean(д),
      диалогВЭкране: Boolean(д) && д.left >= -0.5 && д.top >= -0.5 && д.right <= W + 0.5 && д.bottom <= H + 0.5,
      диалогОткрыт: Boolean(диалог) && диалог.open,
      обрезан: у.scrollWidth > у.clientWidth + 1 || у.scrollHeight > у.clientHeight + 3,
      размерыПрокрутки: у.scrollWidth + '×' + у.scrollHeight + ' / ' + у.clientWidth + '×' + у.clientHeight,
      сверху: Boolean(ц) && (у === ц || у.contains(ц))
    };
  });
  return итог;
}

