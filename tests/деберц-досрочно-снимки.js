/* ---------- Прогон ---------- */

async function прогнать(подменаЭкрана, папка, подменаСтиля) {
  fs.mkdirSync(папка, { recursive: true });
  ПАПКА = папка;
  проверить(СТАРЫЙ_ТЕКСТ_ВЫХОДА.length > 20, 'прежний текст диалога выхода прочитан из деберц.html');
  проверить(СЛОВА_СОГЛАСИЯ.length > 10, 'слова конца по согласию прочитаны из server/партия-по-сети.js');
  const в3 = вид(партия(3), true), в2 = вид(партия(2), false), вКонца = видКонцаПоСогласию();
  проверить(в3.досрочно && в3.досрочно.можноПредложить === true, 'вид на трёх местах несёт поле «досрочно» с можноПредложить (сервер собрал)');
  проверить(!в2.досрочно, 'вид вдвоём без поля «досрочно»');
  проверить(вКонца.деберц && вКонца.деберц.прервана === true && вКонца.деберц.ничья === false, 'вид конца: прервана, но не ничья');
  const сервер = await поднятьСерверФайлов(подменаЭкрана, подменаСтиля);
  const адрес = 'http://127.0.0.1:' + сервер.address().port + '/';
  console.log('=== Деберц: «Предложить закончить» — снимки и замеры ===');
  console.log('файлы: ' + адрес + (подменаЭкрана ? '  (экран подменён: ' + подменаЭкрана + ')' : '') + '\nснимки: ' + папка);
  let браузер = null;
  try {
    браузер = await chromium.launch();
    for (const размер of РАЗМЕРЫ) {
      await случай(браузер, адрес, размер, 'а', 'сведения-3-места', в3, папка, нажатьСведения,
        (с, п, р) => разобратьСведения(с, п, р, true));
      await случай(браузер, адрес, размер, 'б', 'сведения-вдвоём', в2, папка, нажатьСведения,
        (с, п, р) => разобратьСведения(с, п, р, false));
      await случай(браузер, адрес, размер, 'в', 'выход-3-места', в3, папка, нажатьВыйтиИзПартии,
        разобратьПлашкуБот, СЛОВА_БОТ || { строка: '(слова не прочитаны)' });
      await случай(браузер, адрес, размер, 'г', 'выход-вдвоём', в2, папка, нажатьВМеню,
        (с, п, р) => разобратьВыход(с, п, р, false));
      await случай(браузер, адрес, размер, 'д', 'конец-по-согласию', вКонца, папка, null, разобратьКонец);
    }
  } finally {
    if (браузер) await браузер.close();
    сервер.close();
    fs.rmSync(process.env.ДАННЫЕ_ИГРЫ, { recursive: true, force: true });
    console.log('\nСервер файлов закрыт.');
  }
  console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
  process.exitCode = провалов > 0 ? 1 : 0;
}

