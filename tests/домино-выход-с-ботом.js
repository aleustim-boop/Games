const { сделатьДокумент, сделатьПамять, поддельныеЧасы } = require('./поддельный-браузер');
const РАЗМЕТКА = fs.readFileSync(path.join(КОРЕНЬ, 'домино.html'), 'utf8');
const НОВЫЕ_ID_ОКНА = ['дом-подтверждение-заголовок', 'дом-подтверждение-текст', 'дом-остаться'];

/* старая — страница из кэша игрока: в окне подтверждения нет новых id, узлы стоят внутри окна. */
function запуститьЭкран(старая) {
  const документ = сделатьДокумент();
  const память = сделатьПамять(false);
  const идентификаторы = [...new Set([...РАЗМЕТКА.matchAll(/\sid="([^"]+)"/g)].map(с => с[1]).concat(['дом-рейтинг', 'дом-профиль', 'кнопка-лобби-назад']))];
  assert.ok(идентификаторы.length > 50, 'в домино.html нашлось мало узлов: ' + идентификаторы.length);
  if (!старая) for (const id of НОВЫЕ_ID_ОКНА) assert.ok(идентификаторы.includes(id), 'в домино.html нет узла ' + id);
  for (const id of идентификаторы) {
    if (старая && НОВЫЕ_ID_ОКНА.includes(id)) continue;
    const узел = документ.createElement('div');
    узел.id = id;
    if (id.startsWith('экран-') || id === 'дом-настройки') узел.className = 'экран';
    узел.open = false;
    узел.showModal = () => { узел.open = true; };
    узел.close = () => { узел.open = false; };
    документ.body.appendChild(узел);
    if (id === 'дом-итог-середина') узел.appendChild(документ.createElement('details'));
  }
  if (старая) {
    // Как в прежнем домино.html: <h2>, <p>, кнопка «да» с id, кнопка «нет» в форме без id.
    const окно = документ.getElementById('дом-подтверждение');
    const заголовок = документ.createElement('h2'); заголовок.textContent = 'Сдаться?';
    const текст = документ.createElement('p'); текст.textContent = ТЕКСТ_ОКНА_СДАЧА;
    const форма = документ.createElement('form'); const нет = документ.createElement('button'); нет.textContent = 'Продолжить игру';
    форма.appendChild(нет);
    окно.appendChild(заголовок); окно.appendChild(текст); окно.appendChild(документ.getElementById('дом-сдаться')); окно.appendChild(форма);
  }
  const вызовы = [];
  let двери = null, стрелка = null;
  const окно = {
    document: документ, localStorage: память, addEventListener() {}, matchMedia: () => ({ matches: false }),
    ДоминоПравила: П, ДоминоБот: Б,
    ДоминоКости: { кость: () => документ.createElement('div'), цепь() {} },
    ДоминоПамять: { восстановить() { return null; } },
    ДеберцСказать: () => ({ открыть() {}, принять() {} }),
    ЛистЕщё: { подключить: н => { двери = н.двери; return { освежитьКнопкуНастроек() {}, открыт: () => false, закрыть() {}, открыть() {} }; } },
    ЭкранРейтинга: { открыть() {}, открытьСчёт() {} },
    Телеграм: { показатьСтрелку: ф => { стрелка = ф; } },
    Сеть: {
      отправитьХод: async ход => { вызовы.push({ дверь: 'отправитьХод', ход }); return { принято: true }; },
      покинутьПартию: () => { вызовы.push({ дверь: 'покинутьПартию' }); }
    }
  };
  const песочница = {
    window: окно, document: документ, localStorage: память, location: { href: '' }, console,
    setTimeout, clearTimeout, setInterval: () => 0, Date: поддельныеЧасы(1000000).Дата, matchMedia: окно.matchMedia
  };
  vm.createContext(песочница);
  vm.runInContext(fs.readFileSync(ФАЙЛ_ЭКРАНА, 'utf8'), песочница, { filename: 'домино-экран.js' });
  assert.ok(двери && двери.завершить, 'экран не передал листу дверь «завершить»');
  const узел = id => документ.getElementById(id);
  return {
    окно, узел, вызовы, двери: () => двери, документ,
    показать: вид => окно.ИграПоСети.показатьВид(вид),
    назад: () => { assert.equal(typeof стрелка, 'function', 'экран не отдал стрелку «назад»'); стрелка(); },
    экранВиден: id => узел(id).classList.contains('экран--виден')
  };
}

let номерВида = 0;
/* Вид стола в том виде, как его присылает сервер домино. Ход — не мой (я — место 0),
   чтобы подсказка показывала события, а не «Выберите кость». */
function видСтола({ мест = 3, досрочно = ПОЛЕ, застолом = null, номерСобытия = 1 } = {}) {
  const п = Д.раздать(null, { игроки: ['и1', 'и2', 'и3', 'и4'].slice(0, мест) });
  const в = Д.видДляИгрока(п, 'и1', { код: 'ТЕСТ', версия: ++номерВида, номерСобытия });
  в.сыграноПартий = 0;
  в.домино.ход = 1;
  if (досрочно) в.досрочно = досрочно;
  if (застолом) в.застолом = застолом;
  return в;
}
