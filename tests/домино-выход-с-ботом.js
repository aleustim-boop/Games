function сделатьКопию(папка, поломка, номер) {
  const текст = fs.readFileSync(ЭКРАН, 'utf8');
  if (текст.split(поломка.было).length - 1 !== 1) return null;
  const копия = path.join(папка, 'копия-' + номер + '.js');
  fs.writeFileSync(копия, текст.replace(поломка.было, () => поломка.стало));
  return копия;
}

function ломающиеЗапуски() {
  console.log('Ломающие запуски на копии');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'домино-выход-'));
  let строкаНеНашлась = false;
  try {
    ПОЛОМКИ.forEach((поломка, номер) => {
      const копия = сделатьКопию(папка, поломка, номер);
      if (!копия) {
        console.log('  НЕ НАШЛАСЬ строка для порчи ' + поломка.имя + ': ' + поломка.было);
        строкаНеНашлась = true;
        return;
      }
      const итог = spawnSync(process.execPath, [__filename, '--экран', копия], { encoding: 'utf8', timeout: 90000 });
      const вывод = (итог.stdout || '') + (итог.stderr || '');
      const строкаИтога = вывод.match(/Итого проверок: (\d+), провалов: (\d+)/) || [];
      проверка('ломающий запуск ' + поломка.имя + ' краснеет', () => {
        assert.ok(итог.status === 1 && Number(строкаИтога[2]) > 0, 'код ' + итог.status + ', ' + (строкаИтога[0] || 'итога нет') + '\n' + вывод.slice(-500));
        const красные = вывод.split('\n').filter(с => с.includes('ПРОВАЛ  '));
        assert.ok(красные.some(с => с.includes(поломка.провалит)), 'покраснело не то: нужна «' + поломка.провалит + '», красные: ' + красные.join(' | ').slice(0, 300));
      });
    });
  } finally {
    fs.rmSync(папка, { recursive: true, force: true });
  }
  return строкаНеНашлась;
}

