/* =====================================================================
   Насколько распухает рука у ПЛОХОГО игрока.

   Прошлый скрипт («сколько-карт-в-руке.js») играл обеими сторонами
   штатным ботом — он играет разумно и руку до огромных размеров
   не доводит. Но живой новичок часто жмёт «Беру» вместо того, чтобы
   отбиваться, и карты у него копятся.

   Здесь человек играет нарочно плохо: защищаться даже не пытается,
   всегда забирает стол, а нападает всегда одной самой мелкой картой
   (чтобы соперник успевал подкидывать). Это верхняя честная граница
   того, что игра может показать на экране.

   Запуск:  node tests/сколько-карт-у-плохого-игрока.js [сколько партий]
   ===================================================================== */

'use strict';

const игра = require(require('path').join(__dirname, '..', 'js', 'game.js'));

const ПАРТИЙ = Number(process.argv[2]) || 3000;
const ПРЕДЕЛ_ХОДОВ = 600;

let зерно = 777001;
Math.random = function () {
  зерно = (зерно * 1103515245 + 12345) % 2147483648;
  return зерно / 2147483648;
};

/** Ход «плохого» человека: не отбивается никогда, кладёт всегда самую мелкую. */
function ходПлохого(партия) {
  const текущая = игра.фаза(партия);
  const рука = партия.руки.человек;

  if (текущая === 'защита') {
    // Даже не смотрим, можем ли отбиться, — сразу берём
    игра.объявитьБеру(партия);
    return true;
  }

  if (текущая === 'атака' || текущая === 'подкидывание' || текущая === 'докидывание') {
    let лучший = -1;
    for (let i = 0; i < рука.length; i++) {
      if (!игра.можноПоложить(партия, рука[i])) continue;
      if (лучший === -1 || рука[i].вес < рука[лучший].вес) лучший = i;
    }
    if (лучший === -1) { игра.завершитьПодход(партия); return true; }
    игра.положитьВАтаку(партия, 'человек', лучший);
    return true;
  }
  игра.завершитьПодход(партия);
  return true;
}

function сыграть(сложность) {
  const партия = игра.создатьПартию(сложность);
  let макс = 6;
  let ходов = 0;
  while (!партия.завершена && ходов < ПРЕДЕЛ_ХОДОВ) {
    const чей = игра.ктоХодит(партия);
    if (чей === 'человек') {
      ходПлохого(партия);
    } else {
      if (!игра.ходБота(партия, 'бот', сложность)) игра.завершитьПодход(партия);
    }
    if (партия.руки.человек.length > макс) макс = партия.руки.человек.length;
    ходов++;
  }
  return { макс: макс, доиграна: партия.завершена };
}

console.log('=== Рука новичка, который всегда берёт ===');
console.log('партий на уровень:', ПАРТИЙ);
console.log('');

const границы = [15, 18, 20, 22, 24, 26, 30, 35];

for (const сложность of ['лёгкий', 'обычный', 'сложный']) {
  let всегоМакс = 0, сумма = 0, недоиграно = 0;
  const дошло = {};
  for (const г of границы) дошло[г] = 0;

  for (let i = 0; i < ПАРТИЙ; i++) {
    const и = сыграть(сложность);
    if (!и.доиграна) недоиграно++;
    сумма += и.макс;
    if (и.макс > всегоМакс) всегоМакс = и.макс;
    for (const г of границы) if (и.макс >= г) дошло[г]++;
  }

  console.log('--- соперник «' + сложность + '» ---');
  console.log('  самая большая рука:', всегоМакс, 'карт');
  console.log('  в среднем максимум за партию:', (сумма / ПАРТИЙ).toFixed(1));
  for (const г of границы) {
    console.log('  до ' + String(г).padStart(2) + ' карт и больше: ' +
                String(дошло[г]).padStart(5) + ' из ' + ПАРТИЙ +
                '  (' + (дошло[г] / ПАРТИЙ * 100).toFixed(1) + '%)');
  }
  if (недоиграно) console.log('  ВНИМАНИЕ: не доиграно партий:', недоиграно);
  console.log('');
}
