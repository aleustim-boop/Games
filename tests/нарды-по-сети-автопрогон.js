/**
 * Хозяин создаёт стол, гость входит. Возвращает { первый, второй } —
 * двух живых игроков, обоим уже пришёл снимок партии.
 *
 * Если сервер ответит на /создать отказом (обычно потому что реестр
 * игру «нарды» пока не знает), возвращает { ошибкаРеестра: true, ответ }
 * и партию не заводит — это фиксируется как ПРОВАЛ проверки «сервер
 * знает игру нарды», не как молчаливый пропуск.
 */
async function завестиПартию(клиент, настройки, подпись) {
  /* Настройки едут ПЛОСКО, рядом с «игра» и «имя». Так их шлёт настоящий
     браузер (js/сеть.js, «телоСоздания»), и так их читает сервер: дверь
     /создать отдаёт тело целиком в создатьКомнату, а «применитьНастройки»
     берёт из него «вариантНард» без всякой обёртки. Вложи мы их в поле
     «настройки», сервер бы их не увидел вовсе и молча раздал короткие —
     и проверка длинных нард краснела бы всегда, даже на здоровом сервере. */
  const телоСоздания = Object.assign({ игра: 'нарды', имя: 'Хозяин' }, настройки || {});
  const создание = await клиент.запрос('/создать', телоСоздания);
  сторож.осмотретьКонверт(создание.данные, 'создание (' + подпись + ')');

  const создалось = создание.номер === 200 && создание.данные && typeof создание.данные.код === 'string';
  проверить(создалось,
    подпись + ': сервер знает игру «нарды» и создал комнату (получили ' + создание.номер + ' «' +
    ((создание.данные && создание.данные.ошибка) || JSON.stringify(создание.данные)) + '»)');
  if (!создалось) return { ошибкаРеестра: true, ответ: создание };

  const хозяин = new Игрок('Хозяин (' + подпись + ')', клиент, создание.данные.код, создание.данные.пропуск, создание.данные.состояние);

  const вход = await клиент.запрос('/войти', { код: создание.данные.код, имя: 'Гость' });
  сторож.осмотретьКонверт(вход.данные, 'вход (' + подпись + ')');
  проверить(вход.номер === 200 && вход.данные && typeof вход.данные.пропуск === 'string',
    подпись + ': второй игрок смог войти в комнату (получили ' + вход.номер + ')');
  if (!(вход.номер === 200 && вход.данные && вход.данные.пропуск)) return { ошибкаРеестра: true, ответ: вход };

  const гость = new Игрок('Гость (' + подпись + ')', клиент, создание.данные.код, вход.данные.пропуск, вход.данные.состояние);

  await хозяин.обновить();
  await гость.обновить();

  проверить(хозяин.вид.игра === 'нарды' && гость.вид.игра === 'нарды', подпись + ': оба видят игру «нарды»');
  проверить(хозяин.вид.мойЦвет !== гость.вид.мойЦвет, подпись + ': цвета розданы разные');
  проверить(['белые', 'чёрные'].indexOf(хозяин.вид.мойЦвет) !== -1 && ['белые', 'чёрные'].indexOf(гость.вид.мойЦвет) !== -1,
    подпись + ': цвета названы словами «белые»/«чёрные»');

  const первый = хозяин.вид.мойЦвет === 'белые' ? хозяин : гость;
  const второй = первый === хозяин ? гость : хозяин;
  return { первый: первый, второй: второй };
}

