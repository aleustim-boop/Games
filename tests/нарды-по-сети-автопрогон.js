class Игрок {
  constructor(имя, клиент, код, пропуск, вид) {
    this.имя = имя;
    this.клиент = клиент;
    this.код = код;
    this.пропуск = пропуск;
    this.вид = вид || null;
    if (вид) сторож.осмотреть(вид, this.имя);
  }

  async обновить() {
    const о = await this.клиент.запрос('/состояние', { код: this.код, пропуск: this.пропуск });
    проверить(о.номер === 200, this.имя + ': /состояние ответило ' + о.номер);
    сторож.осмотретьКонверт(о.данные, this.имя);
    if (о.данные && о.данные.состояние) {
      this.вид = о.данные.состояние;
      сторож.осмотреть(this.вид, this.имя);
    }
    return this.вид;
  }

  async ход(намерение) {
    const тело = Object.assign({ код: this.код, пропуск: this.пропуск }, намерение);
    const о = await this.клиент.запрос('/ход', тело);
    сторож.осмотретьКонверт(о.данные, this.имя);
    if (о.данные && о.данные.состояние) {
      this.вид = о.данные.состояние;
      сторож.осмотреть(this.вид, this.имя);
    }
    return о.данные || {};
  }

  выйти() { return this.клиент.запрос('/выйти', { код: this.код, пропуск: this.пропуск }); }
}

