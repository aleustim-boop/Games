async function ломающийЗапуск() {
  console.log('=== ЛОМАЮЩИЙ ЗАПУСК: в копии server/комнаты.js «вариантНард» не доезжает до раздачи партии ===\n');

  const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'нарды-по-сети-'));
  console.log('  копия сервера: ' + врем);
  const ПАПКА_ДАННЫХ = path.join(КОРЕНЬ, 'server', 'данные');
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(врем, 'server'), {
    recursive: true,
    filter: function (откуда) { return откуда !== ПАПКА_ДАННЫХ && !откуда.startsWith(ПАПКА_ДАННЫХ + path.sep); }
  });
  fs.cpSync(path.join(КОРЕНЬ, 'js'), path.join(врем, 'js'), { recursive: true });

  const файлКомнат = path.join(врем, 'server', 'комнаты.js');
  const текст = fs.readFileSync(файлКомнат, 'utf8');
  // «\b» кириллицу не знает: соседей ключа проверяем явно, не буквой/цифрой/подчёркиванием ни слева, ни справа.
  const шаблон = /(^|[^A-Za-zА-Яа-яЁё0-9_])вариантНард(\s*:)/g;
  const совпадения = текст.match(шаблон) || [];

  if (совпадения.length !== 1) {
    console.log('ЛОМАЮЩИЙ ЗАПУСК НЕ СОСТОЯЛСЯ: передача «вариантНард» в раздачу партии найдена в копии ' +
      совпадения.length + ' раз(а), а нужно ровно один.');
    console.log('Скорее всего Э3 плана «нарды по сети» ещё не приехал — в server/комнаты.js этого поля попросту нет.');
    fs.rmSync(врем, { recursive: true, force: true });
    process.exit(2);
    return;
  }

  const порченый = текст.replace(шаблон, function (совпало, слева, двоеточие) { return слева + 'вариантНардОтключёнЛомающимПрогоном' + двоеточие; });
  fs.writeFileSync(файлКомнат, порченый, 'utf8');
  console.log('  поле «вариантНард» в копии переименовано — до раздачи больше не доедет');

  let сервер = null;
  try {
    сервер = await поднятьСервер(path.join(врем, 'server', 'сервер.js'), [String(ПОРТ + 1), '--без-памяти']);
    console.log('  порченый сервер поднят на ' + (ПОРТ + 1) + ' (pid ' + сервер.pid + ')');

    const клиент = создатьКлиента(ПОРТ + 1);
    await проверитьДлинныеНарды(клиент, false);
  } catch (сбой) {
    console.error('Ломающий прогон сорвался:', сбой && сбой.stack || сбой);
    провалы.push('ломающий прогон сорвался — ' + (сбой && сбой.message || сбой));
    проверок++;
  } finally {
    if (сервер) сервер.kill();
  }

  fs.rmSync(врем, { recursive: true, force: true });

  console.log('');
  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалы.length);

  const покраснелоНужное = провалы.some(function (п) { return /^длинные:/.test(п); });
  if (покраснелоНужное) {
    console.log('Ломающий запуск покраснел на нужном месте — на расстановке длинных нард:');
    провалы.filter(function (п) { return /^длинные:/.test(п); }).forEach(function (п) { console.log('   ' + п); });
    process.exit(1);
  } else {
    console.log('ПЛОХО: порченый сервер прошёл проверку расстановки длинных нард без единого провала — проверка смотрит не туда');
    process.exit(1);
  }
}

