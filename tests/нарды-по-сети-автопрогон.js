  const карточное = await ходит.ход({ действие: 'ходить', карта: 0 });
  проверить(карточное.принято === false, 'сервер принял карточное действие («ходить», карта) в нардовой комнате');
  console.log('  карточное действие в нардах: «' + карточное.причина + '»');

  const выдуманный = await ходит.ход({ действие: 'ход', шаги: [{ откуда: 97, куда: 3, кубик: 1 }] });
  проверить(выдуманный.принято === false, 'сервер принял выдуманный ход с несуществующего пункта 97');
  проверить(typeof выдуманный.причина === 'string' && выдуманный.причина.length > 3,
    'на выдуманный ход сервер не объяснил словами, почему отказал');
  console.log('  выдуманный ход: «' + выдуманный.причина + '»');

  if (!ходит.вид.бросок) {
    const первыйБросок = await ходит.ход({ действие: 'бросить' });
    проверить(первыйБросок.принято === true, 'бросок для проверки повторного броска не приняли — «' + первыйБросок.причина + '»');
  }
  const второйБросок = await ходит.ход({ действие: 'бросить' });
  проверить(второйБросок.принято === false, 'сервер принял второй бросок подряд');
  console.log('  второй бросок подряд: «' + второйБросок.причина + '»');
