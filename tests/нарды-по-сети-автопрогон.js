async function сыгратьПартию(белые, чёрные, подпись) {
  const итоги = { ходов: 0, пропусков: 0, бросков: 0 };

  for (let шаг = 0; шаг < ПОТОЛОК_ХОДОВ; шаг++) {
    await белые.обновить();
    await чёрные.обновить();

    проверить(белые.вид.завершена === чёрные.вид.завершена,
      подпись + ': один игрок думает, что партия кончилась, а другой нет (шаг ' + шаг + ')');
    if (белые.вид.завершена) return итоги;

    проверить(белые.вид.яХожу !== чёрные.вид.яХожу,
      подпись + ': по мнению обоих ходят либо оба сразу, либо никто (шаг ' + шаг + ')');

    const ходит = белые.вид.яХожу ? белые : чёрные;
    const ждёт = ходит === белые ? чёрные : белые;

    проверить(ждёт.вид.ходитьНечем === false, подпись + ': у ждущего игрока вид.ходитьНечем не false (шаг ' + шаг + ')');

    if (!ходит.вид.бросок) {
      const брошено = await ходит.ход({ действие: 'бросить' });
      проверить(брошено.принято === true, подпись + ': сервер не принял бросок кубиков — «' + брошено.причина + '» (шаг ' + шаг + ')');
      if (!брошено.принято) return итоги;
      итоги.бросков++;
      проверить(Array.isArray(ходит.вид.бросок) && ходит.вид.бросок.length === 2 &&
        ходит.вид.бросок.every(function (к) { return Number.isInteger(к) && к >= 1 && к <= 6; }),
        подпись + ': бросок пришёл не парой граней 1..6 (' + JSON.stringify(ходит.вид.бросок) + ')');
    }

    const { партия: своя, ходы } = ходыИзВида(ходит.вид);
    const действительноНечем = нечемХодить(ходы);
    проверить(ходит.вид.ходитьНечем === действительноНечем,
      подпись + ': вид.ходитьНечем (' + ходит.вид.ходитьНечем + ') разошёлся с правилами (' + действительноНечем + '), шаг ' + шаг);

    /* Пересверка сервера не его же числом. «максимумКубиков» приезжает в
       снимке от сервера; пересчитываем тот же бросок на той же доске сами
       и отдельно смотрим, есть ли вообще хоть одно перемещение. Если
       сервер однажды объявит тупик там, где ходы есть, живой игрок получит
       «пропуск» вместо хода — краснеть должно здесь. */
    if (своя.сыграно.length === 0 && Array.isArray(ходит.вид.бросок)) {
      пересчётовБроска++;
      const пересчитанный = пересчитатьМаксимумКубиков(своя, ходит.вид.бросок);
      проверить(пересчитанный === ходит.вид.максимумКубиков,
        подпись + ': сервер обещал ' + ходит.вид.максимумКубиков + ' кубик(ов) к игре, а тот же бросок ' +
        JSON.stringify(ходит.вид.бросок) + ' даёт ' + пересчитанный + ' (шаг ' + шаг + ')');
      проверить(естьХотяБыОдноПеремещение(своя) === !действительноНечем,
        подпись + ': «ходить нечем» не сходится с доской — перемещения есть, а ход объявлен пустым (шаг ' + шаг + ')');
    }

    if (действительноНечем) {
      const ответ = await ходит.ход({ действие: 'ход', шаги: [] });
      проверить(ответ.принято === true, подпись + ': пропуск при «ходить нечем» не приняли — «' + ответ.причина + '» (шаг ' + шаг + ')');
      итоги.пропусков++;
      continue;
    }

    const выбранный = случайныйХод(ходы);
    const шагиОтправки = шагиДляОтправки(выбранный);

    const проверочная = Правила.копияПартии(своя);
    const сыгралосьВПравилах = Правила.сделатьХод(проверочная, { шаги: шагиОтправки });
    проверить(сыгралосьВПравилах !== null, подпись + ': ход, который сами же правила и предложили, правила не приняли (шаг ' + шаг + ')');
    const ждёмДоску = Правила.картинкаПартии(проверочная);

    const мойЦветДоХода = ходит.вид.мойЦвет;
    const броскиДоХода = ходит.вид.бросок ? ходит.вид.бросок.slice() : null;

    const ответ = await ходит.ход({ действие: 'ход', шаги: шагиОтправки });
    проверить(ответ.принято === true,
      подпись + ': сервер не принял ход, законный по правилам — «' + шагиОтправки.map(function (ш) { return ш.откуда + '→' + ш.куда; }).join(', ') +
      '»: «' + ответ.причина + '» (шаг ' + шаг + ')');
    if (!ответ.принято) return итоги;
    итоги.ходов++;

    проверить(отпечатокДоски(ходит.вид) === JSON.stringify(ждёмДоску),
      подпись + ': доска сервера после хода разошлась с тем, что дают правила (шаг ' + шаг + ')');

    const пх = ходит.вид.последнийХод;
    проверить(!!пх, подпись + ': сервер не рассказал ходившему, каким был его последний ход (шаг ' + шаг + ')');
    if (пх) {
      проверить(пх.мой === true, подпись + ': свой же ход пришёл ходившему помеченным как чужой (шаг ' + шаг + ')');
      проверить(пх.чей === мойЦветДоХода, подпись + ': в последнемХоде назван цвет «' + пх.чей + '», а ходил ' + мойЦветДоХода);
      проверить(совпалиШаги(пх.шаги, шагиОтправки), подпись + ': шаги в последнемХоде у ходившего разошлись с отправленными (шаг ' + шаг + ')');
      проверить(typeof пх.запись === 'string' && пх.запись.length > 0, подпись + ': запись хода не пришла словами (шаг ' + шаг + ')');

      await ждёт.обновить();
      const чужой = ждёт.вид.последнийХод;
      проверить(!!чужой, подпись + ': сопернику последний ход не пришёл вовсе (шаг ' + шаг + ')');
      if (чужой) {
        проверить(чужой.мой === false, подпись + ': чужой ход помечен сопернику как свой (шаг ' + шаг + ')');
        проверить(чужой.чей === пх.чей, подпись + ': сопернику цвет хода назван иначе — «' + чужой.чей + '» вместо «' + пх.чей + '»');
        проверить(чужой.чей !== ждёт.вид.мойЦвет, подпись + ': цвет чужого хода совпал с цветом того, кто его получил');
        проверить(совпалиШаги(чужой.шаги, шагиОтправки), подпись + ': у соперника шаги последнего хода разошлись с отправленными (шаг ' + шаг + ')');
        проверить(JSON.stringify(чужой.бросок) === JSON.stringify(броскиДоХода),
          подпись + ': бросок в последнемХоде у соперника (' + JSON.stringify(чужой.бросок) + ') не совпал с тем, что был у ходившего (' + JSON.stringify(броскиДоХода) + ')');
      }

      const словами = JSON.stringify(пх);
      проверить(!/перв(ый|ого)|втор(ой|ого)|бот/i.test(словами),
        подпись + ': в рассказе о последнем ходе видно внутреннее имя места — ' + словами.slice(0, 160));
    }
  }

  проверить(false, подпись + ': партия не кончилась за ' + ПОТОЛОК_ХОДОВ + ' ходов — похоже, встала');
  return итоги;
}

function сверитьИтог(белые, чёрные, подпись) {
  проверить(белые.вид.завершена === true && чёрные.вид.завершена === true, подпись + ': партия завершена у обоих');
  проверить(!!белые.вид.итог && !!чёрные.вид.итог, подпись + ': итог партии пришёл обоим');
  if (!белые.вид.итог || !чёрные.вид.итог) return;

  проверить(белые.вид.итог.яВыиграл !== чёрные.вид.итог.яВыиграл, подпись + ': итог.яВыиграл — выиграл ровно один из двоих');
  проверить(белые.вид.итог.победитель === чёрные.вид.итог.победитель, подпись + ': победитель назван обоим одинаково');
  проверить(['белые', 'чёрные'].indexOf(белые.вид.итог.победитель) !== -1, подпись + ': победитель назван цветом');
  проверить(Number.isInteger(белые.вид.итог.цена) && белые.вид.итог.цена >= 1 && белые.вид.итог.цена <= 3,
    подпись + ': цена от 1 до 3 (пришло ' + белые.вид.итог.цена + ', вид «' + белые.вид.итог.видПобеды + '»)');
  проверить(typeof белые.вид.итог.причина === 'string' && белые.вид.итог.причина.length > 0, подпись + ': причина конца партии словами');
}

/* =====================================================================
   ЧАСТЬ 7. РЕВАНШ
   ===================================================================== */

async function проверитьРеванш(белые, чёрные, подпись) {
  console.log('\n=== ' + подпись + ': реванш ===');

  const проигравший = белые.вид.итог.яВыиграл === false ? белые : чёрные;
  const победитель = проигравший === белые ? чёрные : белые;

  const ещё1 = await белые.ход({ действие: 'ещё' });
  проверить(ещё1.принято === true, подпись + ': хозяин не смог попросить реванш — «' + ещё1.причина + '»');
  const ещё2 = await чёрные.ход({ действие: 'ещё' });
  проверить(ещё2.принято === true, подпись + ': гость не смог согласиться на реванш — «' + ещё2.причина + '»');

  await белые.обновить();
  await чёрные.обновить();

  проверить(белые.вид.завершена === false && чёрные.вид.завершена === false, подпись + ': после реванша партия снова идёт у обоих');
  проверить(!белые.вид.последнийХод && !чёрные.вид.последнийХод, подпись + ': прошлый последнийХод не перекочевал в новую партию');

  проверить(проигравший.вид.мойЦвет === 'белые' && проигравший.вид.яХожу === true,
    подпись + ': реванш — прошлый проигравший садится белыми и ходит первым');
  проверить(победитель.вид.мойЦвет === 'чёрные',
    подпись + ': реванш — прошлый победитель садится чёрными');
}

/* =====================================================================
   ЧАСТЬ 8. СДАЧА
   ===================================================================== */

async function проверитьСдачу(клиент) {
  console.log('\n=== Сдача ===');
  const пара = await завестиПартию(клиент, {}, 'сдача');
  if (пара.ошибкаРеестра) return пара;
  const { первый: белые, второй: чёрные } = пара;

  const сдался = await белые.ход({ действие: 'сдаться' });
  проверить(сдался.принято === true, 'сдача: сервер не принял сдачу — «' + сдался.причина + '»');

  await белые.обновить();
  await чёрные.обновить();

  проверить(белые.вид.завершена === true && чёрные.вид.завершена === true, 'сдача: партия завершена у обоих сразу');
  if (белые.вид.итог && чёрные.вид.итог) {
    проверить(белые.вид.итог.видПобеды === 'сдача', 'сдача: видПобеды — «сдача» (пришло «' + белые.вид.итог.видПобеды + '»)');
    проверить(белые.вид.итог.цена === 1, 'сдача: цена — 1 (пришло ' + белые.вид.итог.цена + ')');
    проверить(белые.вид.итог.победитель === чёрные.вид.мойЦвет, 'сдача: победил тот, кто не сдавался');
    проверить(белые.вид.итог.яВыиграл === false && чёрные.вид.итог.яВыиграл === true, 'сдача: сдавшийся проиграл');
  }

  await белые.выйти();
  await чёрные.выйти();
  return {};
}

/* =====================================================================
   ЧАСТЬ 9. ДЛИННЫЕ НАРДЫ — РАССТАНОВКА (И ПАРТИЯ ДО КОНЦА)
   ===================================================================== */

async function проверитьДлинныеНарды(клиент, доигрывать) {
  console.log('\n=== Длинные нарды ===');
  const пара = await завестиПартию(клиент, { вариантНард: 'длинные' }, 'длинные');
  if (пара.ошибкаРеестра) return пара;
  const { первый: белые, второй: чёрные } = пара;

  проверить(белые.вид.вариант === 'длинные', 'длинные: вид.вариант — «длинные» (пришло «' + белые.вид.вариант + '»)');

  const своя = партияИзВида(белые.вид);
  const головаБелых = Правила.голова(своя, Правила.БЕЛЫЕ);
  const наГолове = Правила.пункт(своя, головаБелых).сколько;
  проверить(наГолове === 15, 'длинные: на голове у белых сразу все 15 шашек (пришло ' + наГолове + ')');

  const ожидаемая = Правила.картинкаПартии(Правила.создатьПартию({ вид: Правила.ДЛИННЫЕ, первый: Правила.БЕЛЫЕ }));
  проверить(JSON.stringify(белые.вид.доска) === JSON.stringify(ожидаемая),
    'длинные: расстановка в первом снимке совпадает с тем, что строят правила для варианта «длинные» (а не короткая)');

  if (!доигрывать) {
    await белые.выйти();
    await чёрные.выйти();
    return {};
  }

  await проверитьОтказы(белые, чёрные);
  await сыгратьПартию(белые, чёрные, 'длинные');
  сверитьИтог(белые, чёрные, 'длинные');

  await белые.выйти();
  await чёрные.выйти();
  return {};
}

/* =====================================================================
   ЧАСТЬ 10. ГЛАВНЫЙ ПРОГОН
   ===================================================================== */

async function главныйПрогон(клиент) {
  console.log('\n=== Короткие нарды: партия на двоих ===');
  const пара = await завестиПартию(клиент, {}, 'короткие');
  if (пара.ошибкаРеестра) return пара;
  const { первый: белые, второй: чёрные } = пара;

  await проверитьОтказы(белые, чёрные);
  await сыгратьПартию(белые, чёрные, 'короткие');
  сверитьИтог(белые, чёрные, 'короткие');

  if (белые.вид.итог) await проверитьРеванш(белые, чёрные, 'короткие');

  await сыгратьПартию(белые, чёрные, 'короткие (реванш)');
  сверитьИтог(белые, чёрные, 'короткие (реванш)');

  await белые.выйти();
  await чёрные.выйти();

  const итогСдачи = await проверитьСдачу(клиент);
  if (итогСдачи && итогСдачи.ошибкаРеестра) return итогСдачи;

  const итогДлинных = await проверитьДлинныеНарды(клиент, true);
  if (итогДлинных && итогДлинных.ошибкаРеестра) return итогДлинных;

  return {};
}

