/** Живая партия правил, собранная из снимка, который прислал сервер. */
function партияИзВида(вид) { return Правила.партияИзКартинки(вид.доска); }

/** Список законных ходов в текущей позиции. */
function ходыИзВида(вид) {
  const партия = партияИзВида(вид);
  return { партия: партия, ходы: Правила.возможныеХоды(партия) };
}

/**
 * Ходить нечем? Смотрим НЕ на длину списка ходов, а на то, что в нём лежит.
 *
 * Правила считают пропуск полноценным ходом: когда сыграть нельзя ни одного
 * кубика, «возможныеХоды» отдают ОДИН ход с пустым списком шагов и записью
 * «пропуск», а вовсе не пустой список. Прежняя мера «ходы.length === 0»
 * принимала такой тупик за обычную позицию — отсюда и брались провалы
 * «вид.ходитьНечем (true) разошёлся с правилами (false)»: сервер был прав,
 * ошибалась проверка.
 */
function нечемХодить(ходы) {
  return ходы.every(function (ход) { return !ход.шаги || ход.шаги.length === 0; });
}

/**
 * Есть ли на доске ХОТЬ ОДНО перемещение — без правила «играй столько
 * кубиков, сколько можешь». Нужно, чтобы не верить серверу на слово:
 * «максимумКубиков» приезжает в снимке от него же, и сверять снимок с
 * самим собой бессмысленно. Здесь фильтр снят (максимум ставим на один
 * кубик больше уже сыгранного), поэтому видны все перемещения подряд.
 */
function естьХотяБыОдноПеремещение(доска) {
  const копия = Правила.копияПартии(доска);
  копия.максимумКубиков = копия.сыграно.length + 1;
  return Правила.возможныеШаги(копия).length > 0;
}

/** Пересчитать тот же бросок с нуля: сколько кубиков сыграть возможно. */
function пересчитатьМаксимумКубиков(доска, бросок) {
  const заново = Правила.копияПартии(доска);
  заново.бросок = null;                       // иначе правила откажутся бросать поверх броска
  Правила.бросить(заново, бросок);
  return Правила.максимумКубиков(заново);
}

function случайныйХод(ходы) { return ходы[Math.floor(Math.random() * ходы.length)]; }

/** Перемещения в виде, в каком их шлёт браузер: только откуда-куда-кубик. */
function шагиДляОтправки(ход) {
  return ход.шаги.map(function (ш) { return { откуда: ш.откуда, куда: ш.куда, кубик: ш.кубик }; });
}

function совпалиШаги(а, б) {
  if (!Array.isArray(а) || !Array.isArray(б) || а.length !== б.length) return false;
  for (let i = 0; i < а.length; i++) {
    if (а[i].откуда !== б[i].откуда || а[i].куда !== б[i].куда || а[i].кубик !== б[i].кубик) return false;
  }
  return true;
}

