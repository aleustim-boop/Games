async function обычныйЗапуск() {
  console.log('=== Нарды по сети: целая партия через сервер комнат (порт ' + ПОРТ + ') ===');
  let сервер = null;
  try {
    сервер = await поднятьСервер(path.join(КОРЕНЬ, 'server', 'сервер.js'), [String(ПОРТ), '--без-памяти']);
    console.log('  сервер комнат поднят на ' + ПОРТ + ' (pid ' + сервер.pid + ')');

    const было = await здоровье(ПОРТ);
    console.log('  сервер жив, комнат до прогона: ' + (было.комнат === undefined ? '(неизвестно)' : было.комнат));

    const клиент = создатьКлиента(ПОРТ);
    await главныйПрогон(клиент);
  } catch (сбой) {
    console.error('Прогон сорвался:', сбой && сбой.stack || сбой);
    провалы.push('прогон сорвался — ' + (сбой && сбой.message || сбой));
    проверок++;
  } finally {
    if (сервер) сервер.kill();
  }

  завершить();
}

function завершить() {
  проверить(пересчётовБроска > 0,
    'бросок сервера ни разу не пересчитан с нуля — сверка «сколько кубиков к игре» не работала');
  console.log('');
  console.log('ответов сервера осмотрено сторожем: ' + (сторож.сколькоОсмотрено ? сторож.сколькоОсмотрено() : '?'));
  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалы.length);
  if (провалы.length > 0) {
    console.log('');
    console.log('!!! НАЙДЕНО ПЛОХОГО: ' + провалы.length);
    Array.from(new Set(провалы)).slice(0, 60).forEach(function (п) { console.log('  - ' + п); });
    process.exit(1);
    return;
  }
  if (проверок === 0) {
    console.log('ПЛОХО: не сделано ни одной проверки — прогон смотрит не туда');
    process.exit(1);
    return;
  }
  console.log('=== Партия по сети играется целиком (короткие и длинные), доска сервера совпадает с правилами, сторож молчит. ===');
  process.exit(0);
}

