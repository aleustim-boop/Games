let тестов = 0;
let провалов = 0;

function проверка(имя, дело) {
  тестов++;
  try {
    дело();
    console.log('✓ ' + имя);
  } catch (ошибка) {
    провалов++;
    console.error('✗ ' + имя);
    console.error('  ' + ошибка.message);
  }
}

function утверждение(условие, сообщение) {
  if (!условие) throw new Error(сообщение);
}

/** Вырезает сбалансированный блок { ... }, начиная с первой { после метки.
    Счётчик скобок, а не регулярка — кириллице и \b тут делать нечего. */
function вырезатьБлок(текст, метка) {
  const позицияМетки = текст.indexOf(метка);
  if (позицияМетки === -1) return null;
  const открывающая = текст.indexOf('{', позицияМетки);
  if (открывающая === -1) return null;
  let глубина = 0;
  for (let i = открывающая; i < текст.length; i++) {
    if (текст[i] === '{') глубина++;
    else if (текст[i] === '}') {
      глубина--;
      if (глубина === 0) return текст.slice(открывающая, i + 1);
    }
  }
  return null;
}

/** Прогоняет все пять пунктов приёма для одного места (файла+функции) над
    переданным текстом. Текст может быть настоящим или испорченным — так
    один и тот же набор проверок используется и в обычном, и в ломающем
    режиме: испорченный код обязан провалить ровно то же самое сито. */
function проверитьМесто(текст, место, приставка) {
  const п = приставка ? '[' + приставка + '] ' : '';

  const тело = вырезатьБлок(текст, 'function ' + место.имяФункции);
  проверка(п + место.метка + ': функцию удаётся разобрать целиком', function () {
    утверждение(тело !== null, 'функция ' + место.имяФункции + ' не найдена или скобки не сбалансированы');
  });
  if (тело === null) return; // дальше разбирать нечего — этого провала выше достаточно, чтобы поймать поломку

  const блокЕслиНетАдреса = вырезатьБлок(тело, 'if (!адрес)');
  const блокOnload = вырезатьБлок(тело, '.onload = function');
  const блокOnerror = вырезатьБлок(тело, '.onerror = function');

  проверка(п + место.метка + ': адрес берётся только через window.Телеграм.фотоИгрока()', function () {
    утверждение(тело.indexOf('window.Телеграм.фотоИгрока()') !== -1, 'вызов фотоИгрока() не найден в теле функции');
    const счётИсточников = тело.split('window.Телеграм.фотоИгрока()').length - 1;
    утверждение(счётИсточников === 1, 'источник адреса в теле функции не один, а ' + счётИсточников);
    утверждение(тело.indexOf('photo_url') === -1, 'найден обход двери — прямое обращение к photo_url помимо фотоИгрока()');
  });

  проверка(п + место.метка + ': new Image() грузится втихую, класс/переменная — не раньше onload', function () {
    const индексImage = тело.indexOf('new Image()');
    утверждение(индексImage !== -1, 'new Image() не найден в теле функции');
    утверждение(блокOnload !== null, 'блок .onload = function не найден');
    const индексOnload = тело.indexOf('.onload = function', индексImage);
    утверждение(индексOnload !== -1 && индексOnload > индексImage, '.onload не найден после создания картинки');
    const зазорДоOnload = тело.slice(индексImage, индексOnload);
    утверждение(зазорДоOnload.indexOf("classList.add('" + место.класс + "')") === -1,
      'класс показа фото ставится ДО onload — до подтверждения загрузки');
    утверждение(зазорДоOnload.indexOf("setProperty('--фото-аватара'") === -1,
      'CSS-переменная ставится ДО onload — до подтверждения загрузки');
    утверждение(
      блокOnload.indexOf("classList.add('" + место.класс + "')") !== -1 ||
      блокOnload.indexOf('показатьЗагруженное()') !== -1,
      'onload не показывает фото ни напрямую, ни через помощника'
    );
  });

  проверка(п + место.метка + ': нет адреса — класс и переменная сняты', function () {
    утверждение(блокЕслиНетАдреса !== null, 'блок if (!адрес) не найден');
    утверждение(блокЕслиНетАдреса.indexOf("classList.remove('" + место.класс + "')") !== -1,
      'при отсутствии адреса класс показа фото не убирается');
    утверждение(блокЕслиНетАдреса.indexOf("removeProperty('--фото-аватара')") !== -1,
      'при отсутствии адреса CSS-переменная не убирается');
  });

  проверка(п + место.метка + ': onerror не показывает фото (кружок остаётся нарисованным)', function () {
    утверждение(блокOnerror !== null, 'блок .onerror = function не найден');
    утверждение(блокOnerror.indexOf("classList.add('" + место.класс + "')") === -1,
      'onerror всё равно ставит класс показа фото — при неудачной загрузке будет пустой кружок');
    утверждение(блокOnerror.indexOf("setProperty('--фото-аватара'") === -1,
      'onerror всё равно ставит CSS-переменную — при неудачной загрузке будет пустой кружок');
  });

  проверка(п + место.метка + ': есть память последнего подтверждённого адреса', function () {
    утверждение(текст.indexOf("let " + место.память + " = ''") !== -1,
      'переменная памяти ' + место.память + ' не объявлена');
    утверждение(тело.indexOf('адрес === ' + место.память) !== -1,
      'повторная загрузка того же адреса не пропускается по памяти');
    утверждение(блокOnload !== null && блокOnload.indexOf(место.память + ' = адрес') !== -1,
      'подтверждение адреса (' + место.память + ' = адрес) происходит не в onload');
  });

  проверка(п + место.метка + ': onload проверяет document.body.contains(' + место.узел + ')', function () {
    утверждение(блокOnload !== null, 'блок .onload = function не найден');
    утверждение(блокOnload.indexOf('document.body.contains(' + место.узел + ')') !== -1,
      'нет проверки document.body.contains перед показом — поздний ответ покрасит выброшенный узел');
  });

  /* ─────────────────────────────────────────────────────────────────────
     ТРОЙНОЙ МЕХАНИЗМ ДЛЯ ЛОББИ (шашки, шахматы, нарды):
     Три источника вызова: load-событие окна, явный вызов в функции показа
     лобби, MutationObserver за классом экран--виден. Дурак архитектурно
     другой (вызов идёт через game.js и показатьЭкран), поэтому для него
     требуем только явный вызов и безопасность.
     ───────────────────────────────────────────────────────────────────── */

  const естьЛоббиВСтруктуре = место.метка.indexOf('шашек') !== -1 ||
                              место.метка.indexOf('шахмат') !== -1 ||
                              место.метка.indexOf('нард') !== -1;

  if (естьЛоббиВСтруктуре) {
    проверка(п + место.метка + ': есть window.addEventListener("load", ...) с вызовом освежения профиля', function () {
      const имеетLoadОбработчик = текст.indexOf("window.addEventListener('load'") !== -1 ||
                                    текст.indexOf('window.addEventListener("load"') !== -1;
      утверждение(имеетLoadОбработчик,
        'load-обработчик не найден — если telegram-web-app.js ответит позже, имя останется заглушкой "Вы"');
    });

    проверка(п + место.метка + ': есть MutationObserver за классом "экран--виден"', function () {
      const имеетMutationObserver = текст.indexOf('new MutationObserver') !== -1;
      утверждение(имеетMutationObserver,
        'MutationObserver не найден — если лобби покажется из чужого файла мимо функции показа, профиль не обновится');
    });

    проверка(п + место.метка + ': MutationObserver смотрит атрибут class и класс "экран--виден"', function () {
      if (текст.indexOf('new MutationObserver') === -1) return; // если нет MutationObserver, эта проверка не применима
      const смотритЭкранВиден = текст.indexOf("'экран--виден'") !== -1 || текст.indexOf('"экран--виден"') !== -1;
      утверждение(смотритЭкранВиден, 'MutationObserver не смотрит класс "экран--виден"');
      const смотритКласс = текст.indexOf("attributeFilter: ['class']") !== -1 ||
                             текст.indexOf('attributeFilter: ["class"]') !== -1;
      утверждение(смотритКласс, 'MutationObserver не смотрит атрибут class');
    });
  }

  проверка(п + место.метка + ': профиль обновляется явно в функции показа (или игра вызывает показ)', function () {
    /* У шашек/шахмат/нард проверяем функцию показатьЛобби.
       У дурака это через game.js, но внутри самого дурака-путь.js есть функции,
       которые вызывают освежитьЛобби при показе. */
    const функцииПоказа = [
      'function показатьЛобби',
      'function показатьТекущий',  // дурак-путь.js
    ];
    let нашлаВызов = false;
    for (const имяФункции of функцииПоказа) {
      if (текст.indexOf(имяФункции) !== -1) {
        const блокФункции = вырезатьБлок(текст, имяФункции);
        if (блокФункции && (блокФункции.indexOf('освежитьПрофиль()') !== -1 ||
                             блокФункции.indexOf('освежитьЛобби()') !== -1 ||
                             блокФункции.indexOf('освежитьАватар()') !== -1)) {
          нашлаВызов = true;
          break;
        }
      }
    }
    утверждение(нашлаВызов || !естьЛоббиВСтруктуре,
      'не найден явный вызов освежения профиля в функции показа — профиль не обновится при возврате в лобби');
  });

  проверка(п + место.метка + ': освежение профиля безопасно при повторных вызовах', function () {
    /* Основной признак безопасности: есть ли проверка на повторный адрес
       в освежитьАватар (через переменную памяти последнего адреса). */
    const имеетПроверкуПовторного = текст.indexOf('если (адрес === последний') !== -1 ||
                                     текст.indexOf('if (адрес === последний') !== -1 ||
                                     (текст.indexOf('if (адрес ===') !== -1 && текст.indexOf('return;') !== -1);
    const имеетПеременнуюПамяти = текст.indexOf(место.память) !== -1;
    const безопасно = имеетПеременнуюПамяти && имеетПроверкуПовторного;
    утверждение(безопасно,
      'функция не защищена от повторных вызовов — может перезагружать картинку, теряя состояние');
  });
}

