        const блок = вырезатьБлок(текст, 'if (!адрес)');
        утверждение(блок !== null, 'блок if (!адрес) для поломки не найден');
        return текст.replace(блок, '{ return; } // ЛОМАЕМ: класс и переменная больше не снимаются');
