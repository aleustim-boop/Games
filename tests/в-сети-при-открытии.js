/* =====================================================================
   «В СЕТИ» ПРИ ОТКРЫТИИ ЛЮБОЙ СТРАНИЦЫ ИГРЫ

   Решение владельца 26.09: друзья видят «в сети» любого, кто в игре, а не
   только того, кто открыл экран «Мои друзья». js/сеть.js сам ставит
   отметку «я здесь» тем же запросом /друзья-онлайн: при загрузке и потом
   раз в полминуты, пока страница видна.

   Что проверяем (node + vm, поддельные window/document/fetch/Telegram
   и поддельные часы — таймеры и Date переставляются рукой):
     1. С подписью Telegram при загрузке уходит ровно один /друзья-онлайн,
        и в нём есть подпись.
     2. Через шаг времени — ещё один.
     3. Страница скрыта — стуков нет, сколько бы времени ни прошло.
     4. Страница снова видна — отметка сразу, не через полминуты.
     5. Экран друзей спросил сразу после отметки — второго запроса нет
        (иначе сервер ответил бы 429), экрану приходит тот же ответ.
     6. Страница открылась скрытой — ни одного стука, пока её не покажут.
     7. Без подписи Telegram — ноль запросов вообще.
   Шаг времени берём из самого js/сеть.js (ОТМЕТКА_ПРИСУТСТВИЯ_КАЖДЫЕ),
   своей копии числа здесь нет.

   Запуск:
     node tests/в-сети-при-открытии.js            — проверить js/сеть.js
     node tests/в-сети-при-открытии.js <путь>     — проверить копию
     node tests/в-сети-при-открытии.js --сломать  — ломающий запуск: копия
         сеть.js во временной папке без вызова отметки при загрузке,
         проверка обязана покраснеть. Файл проекта не трогается.
   ===================================================================== */

