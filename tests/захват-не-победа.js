// Проверка Р31: «2-е место — не победа» (ТЗ 8.7, случаи 38 и 38б) и хвосты пояснения под таблицей мест.
// Запуск:  node tests/захват-не-победа.js            — обычный прогон (без браузера)
//          node tests/захват-не-победа.js --сломать  — портит КОПИИ экрана и онлайна во временной папке, требует провала
// Доводы: --экран <путь к игры/захват/захват-экран.js>, --онлайн <путь к игры/захват/захват-онлайн.js>, --папка <куда класть копии при --сломать>.
// Функции вытаскиваются из настоящих файлов (вторых копий текста нет) и гоняются на настоящих «Правила» и «ЗахватРаскрытие».
'use strict';
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const а = process.argv.slice(2);
const довод = (имя) => { const и = а.indexOf(имя); return и === -1 ? null : а[и + 1]; };
const путьЭкрана = довод('--экран') || path.join(КОРЕНЬ, 'игры', 'захват', 'захват-экран.js');
const путьОнлайна = довод('--онлайн') || path.join(КОРЕНЬ, 'игры', 'захват', 'захват-онлайн.js');

const ХВОСТ_2 = '; второе — если очков к концу не меньше, чем на старте';
const ХВОСТ_3 = '; второе и третье — если очков к концу не меньше, чем на старте';
const СЛОВА_ПРИЧИНЫ = 'По очкам после 10 раундов.';

let плохо = 0, всего = 0;
if (а.includes('--сломать')) сломать();
else process.exit(прогон());

function ждать(факт, образец, метка) {
  всего++;
  if (факт !== образец) { плохо++; console.log('ПРОВАЛ — ' + метка + ': вышло ' + JSON.stringify(факт) + ', ждали ' + JSON.stringify(образец)); }
}

// Вытащить функцию (или одну строку «const имя = …;») из исходника; не нашли — провал, а не пропуск.
function взять(текст, имя, файл) {
  let н = текст.indexOf('  function ' + имя + '(');
  let к;
  if (н >= 0) {
    к = текст.indexOf('\n  }\n', н);
    if (к >= 0) к += 4;
  } else {
    н = текст.indexOf('  const ' + имя + ' = ');
    к = н >= 0 ? текст.indexOf('\n', н) : -1;
  }
  if (н < 0 || к < 0) { плохо++; всего++; console.log('ПРОВАЛ — в ' + файл + ' нет «' + имя + '» (ноль найденного — провал)'); return ''; }
  return текст.slice(н, к);
}

// Стол из n мест: место 1 — у 0, остальные по убыванию очков (равенств нет, строки равенства не мешают).
function собратьМеста(мест) {
  const места = [];
  for (let i = 0; i < мест; i++) места.push({ кто: i, место: i + 1, как: 'живой', очки: 20 - i * 3, областей: 20 - i * 3 });
  return места;
}
function имена(мест) { const о = {}; for (let i = 0; i < мест; i++) о[i] = 'Игрок ' + i; return о; }

function прогон() {
  const Правила = require(path.join(КОРЕНЬ, 'игры', 'захват', 'захват-правила.js'));
  const Раскрытие = require(path.join(КОРЕНЬ, 'игры', 'захват', 'захват-раскрытие.js'));
  const экранТекст = fs.readFileSync(путьЭкрана, 'utf8');
  const онлайнТекст = fs.readFileSync(путьОнлайна, 'utf8');

  const частиЭкрана = ['заголовокИтога', 'причинаИтога', 'причинаСРавенством', 'причинаСНеПобедой', 'строкаРавенстваИтога', 'имяВИтоге', 'пояснениеПлюса']
    .map((и) => взять(экранТекст, и, 'захват-экран.js'));
  const частиОнлайна = ['партияОтменена', 'мояСтрока', 'яВПлюсе', 'инфоИзВида', 'заголовокКонца', 'причинаКонца', 'причинаСРавенством', 'причинаИтогаОнлайн', 'другихЛюдей', 'причинаВОкне']
    .map((и) => взять(онлайнТекст, и, 'захват-онлайн.js'));
  if (частиЭкрана.includes('') || частиОнлайна.includes('')) { console.log('Итого проверок: ' + всего + ', провалов: ' + плохо); return 1; }

  const окно = { ЗахватРаскрытие: Раскрытие };
  const э = new Function('Правила', 'window', частиЭкрана.join('\n') + '; return { заголовокИтога, причинаИтога, причинаСНеПобедой, пояснениеПлюса };')(Правила, окно);
  // причинаВОкне — то, что онлайн отдаёт окну итога на самом деле (отказа «ещё» нет, отмены нет).
  const онлайн = (двери) => new Function('window', 'Экран', 'отказЕщё', 'ПРИЧИНА_ОТМЕНЫ',
    частиОнлайна.join('\n') + '; return { заголовокКонца, причинаИтогаОнлайн, причинаВОкне };')(окно, двери, null, 'Партия отменена');
  const дверьЭкрана = { причинаСНеПобедой: э.причинаСНеПобедой };
  const о = онлайн(дверьЭкрана);

  // Дверь на самом деле выставлена наружу — иначе сеть её не достанет (а онлайн молча промолчит).
  ждать(/причинаСНеПобедой: function \(причина, мой, мест, вПлюсе\) \{ return причинаСНеПобедой\(/.test(экранТекст), true, 'ЗахватЭкран выставляет причинаСНеПобедой');

  // Итог для обоих режимов: мой — номер места, победители — кто в плюсе.
  const итогЭкрана = (мест, мойНомер, победители) => {
    const места = собратьМеста(мест);
    return { места, победители, мой: места[мойНомер], вПлюсе: победители.indexOf(мойНомер) !== -1, причина: 'раунды', словами: СЛОВА_ПРИЧИНЫ, имена: имена(мест), я: мойНомер, победитель: 0 };
  };
  const видОнлайна = (мест, мойНомер, победители) => ({
    я: мойНомер,
    игроки: Array.from({ length: мест }, (_, i) => ({ номер: i, имя: 'Игрок ' + i })),
    итог: { места: собратьМеста(мест), победители, причина: 'раунды', словами: СЛОВА_ПРИЧИНЫ }
  });
  const сверить = (метка, мест, мойНомер, победители, причинаЖдём, заголовокЖдём) => {
    const итог = итогЭкрана(мест, мойНомер, победители);
    const з = видОнлайна(мест, мойНомер, победители);
    ждать(э.причинаИтога(итог), причинаЖдём, 'экран: причина, ' + метка);
    ждать(o_причина(з), причинаЖдём, 'онлайн: причина, ' + метка);
    ждать(о.причинаВОкне({ захват: з }), причинаЖдём, 'онлайн: то, что идёт в окно итога, ' + метка);
    ждать(э.заголовокИтога(итог), заголовокЖдём, 'экран: заголовок, ' + метка);
    ждать(о.заголовокКонца(з), заголовокЖдём, 'онлайн: заголовок, ' + метка);
  };
  const o_причина = (з) => о.причинаИтогаОнлайн(з);
  const НЕ_ПОБЕДА = (м) => СЛОВА_ПРИЧИНЫ.replace(/\.$/, '') + '. ' + м + '-е место — не победа: очков к концу меньше, чем на старте';

  // Случай 38б: четверо, я второй, очков меньше, чем на старте — не в плюсе.
  сверить('38б, 4 места, 2-е не в плюсе', 4, 1, [0], НЕ_ПОБЕДА(2), '2-е место');
  // Случай 38: то же, но в плюсе — «победа» и никакой новой строки.
  сверить('38, 4 места, 2-е в плюсе', 4, 1, [0, 1], СЛОВА_ПРИЧИНЫ, '2-е место — победа');
  // Третье из шести не в плюсе — строка со своим номером.
  сверить('6 мест, 3-е не в плюсе', 6, 2, [0, 1], НЕ_ПОБЕДА(3), '3-е место');
  // Третье из четырёх — и так вне верхней половины: строки нет (иначе она бы всем не в плюсе).
  сверить('4 места, 3-е вне половины', 4, 2, [0], СЛОВА_ПРИЧИНЫ, '3-е место');
  // Три места побеждает одно: второе вне половины, строки нет.
  сверить('3 места, 2-е вне половины', 3, 1, [0], СЛОВА_ПРИЧИНЫ, '2-е место');
  // Первое место — «Победа!» без строки.
  сверить('1-е место', 4, 0, [0], СЛОВА_ПРИЧИНЫ, 'Победа!');
  // Выбывший не получает строку.
  {
    const итог = итогЭкрана(4, 1, [0]);
    итог.мой = Object.assign({}, итог.мой, { как: 'сдался' });
    ждать(э.причинаИтога(итог), СЛОВА_ПРИЧИНЫ, 'экран: выбывший без строки');
  }

  // Хвосты пояснения под таблицей (ТЗ 8.7).
  ждать(э.пояснениеПлюса(2), 'Из 2 игроков побеждает только первое место', 'пояснение, 2 места');
  ждать(э.пояснениеПлюса(3), 'Из 3 игроков побеждает только первое место', 'пояснение, 3 места');
  ждать(э.пояснениеПлюса(4), 'Из 4 игроков побеждают два первых места' + ХВОСТ_2, 'пояснение, 4 места');
  ждать(э.пояснениеПлюса(5), 'Из 5 игроков побеждают два первых места' + ХВОСТ_2, 'пояснение, 5 мест');
  ждать(э.пояснениеПлюса(6), 'Из 6 игроков побеждают три первых места' + ХВОСТ_3, 'пояснение, 6 мест');

  console.log('Итого проверок: ' + всего + ', провалов: ' + плохо);
  return плохо ? 1 : 0;
}

function сломать() {
  const папка = довод('--папка') || fs.mkdtempSync(path.join(os.tmpdir(), 'захват-не-победа-'));
  fs.mkdirSync(папка, { recursive: true });
  const экран = fs.readFileSync(путьЭкрана, 'utf8');
  const онлайн = fs.readFileSync(путьОнлайна, 'utf8');
  const порчи = [
    ['экран', 'экран не пишет строку «не победа» совсем', 'if (!мой || мой.как !== \'живой\' || вПлюсе) return причина;', 'return причина;', 0],
    ['экран', 'строка идёт всем не в плюсе (и 3-му из 4)', 'if (мой.место > Правила.числоПобедителей(мест)) return причина;', '', 0],
    ['экран', 'строка и тем, кто в плюсе (случай 38)', "if (!мой || мой.как !== 'живой' || вПлюсе) return причина;", "if (!мой || мой.как !== 'живой') return причина;", 0],
    ['экран', 'хвост пояснения и при 3 местах', 'if (победителей === 2 && мест >= 4) return', 'if (победителей >= 1) return', 0],
    ['экран', 'нет хвоста при 6 местах', 'if (победителей === 3) return', 'if (false) return', 0],
    ['онлайн', 'онлайн не пишет строку', 'причинаИтогаОнлайн(з);', 'причинаСРавенством(з);', 1],
    ['онлайн', 'онлайн считает «в плюсе» наоборот', 'Экран.причинаСНеПобедой(причина, мояСтрока(з), з.итог.места.length, яВПлюсе(з))', 'Экран.причинаСНеПобедой(причина, мояСтрока(з), з.итог.места.length, !яВПлюсе(з))', 1]
  ];
  let красных = 0;
  порчи.forEach(function (п, н) {
    const исходник = п[4] === 0 ? экран : онлайн;
    if (исходник.split(п[2]).length !== 2) { console.log('ПРОВАЛ — место порчи не найдено ровно один раз: ' + п[1]); return; }
    const путь = path.join(папка, 'п' + н + '.js');
    fs.writeFileSync(путь, исходник.replace(п[2], () => п[3]));
    const р = spawnSync(process.execPath, [__filename, п[4] === 0 ? '--экран' : '--онлайн', путь], { encoding: 'utf8' });
    const красная = р.status === 1 && /ПРОВАЛ/.test(р.stdout);
    if (красная) красных++;
    console.log((красная ? 'КРАСНЕЕТ' : 'НЕ КРАСНЕЕТ (плохо)') + ' — ' + п[1] + ' (код ' + р.status + ')');
  });
  const чист = spawnSync(process.execPath, [__filename], { encoding: 'utf8' });
  console.log('Обычный прогон: код ' + чист.status + ' — ' + чист.stdout.trim().split('\n').pop());
  console.log('Красных: ' + красных + ' из ' + порчи.length);
  process.exit(красных === порчи.length && чист.status === 0 ? 0 : 1);
}
