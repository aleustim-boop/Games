const журнал = [];
function поддельныйTelegram(метод, тело) {
  журнал.push({ метод: метод, тело: тело });
  if (метод === 'getMe') return { ok: true, result: { id: 777, is_bot: true, username: ИМЯ_БОТА } };
  if (метод === 'sendMessage') return { ok: true, result: { message_id: журнал.length } };
  if (метод === 'savePreparedInlineMessage') return { ok: true, result: { id: 'pm' + журнал.length } };
  return { ok: false, error_code: 400, description: 'Bad Request' };
}

function подписать(поля, токен) {
  const строки = Object.keys(поля).map(function (к) { return к + '=' + поля[к]; }).sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(токен).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}

function подписьИгрока(номер, имя) {
  const поля = {
    query_id: 'AAF' + номер,
    user: JSON.stringify({ id: номер, first_name: имя, username: 'igrok' + номер }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  const всё = Object.assign({}, поля, { hash: подписать(поля, ТОКЕН_ДЛЯ_ПРОБЫ) });
  return Object.keys(всё).map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(всё[к]); }).join('&');
}

function спросить(путь, тело) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОСТ, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (сбой) { разобрано = null; }
        готово({ код: ответ.statusCode, тело: разобрано || {} });
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

async function проверитьПоСети() {
  console.log('3. Через сервер на порту ' + ПОРТ + ': /позвать и /приглашение для каждой игры');
  знакомые.забытьВсё();
  let игрПрошло = 0;
  const проверено = { чужихМеток: 0 };
  for (let н = 0; н < ОЖИДАНИЕ.length; н++) {
    const ждём = ОЖИДАНИЕ[н];
    const зовущий = 810100 + н, друг = 820100 + н;
    знакомые.запомнитьЗастолье([{ номер: зовущий, имя: 'Аня' }, { номер: друг, имя: 'Боря' }], ждём.игра);

    const стол = await спросить('/создать', { initData: подписьИгрока(зовущий, 'Аня'), игра: ждём.игра, имя: 'Аня' });
    const код = стол.тело.код || '';
    проверить(!!код, ждём.игра + ': стол не создан (' + стол.код + ')');
    if (!код) continue;
    const ссылка = ссылкаЗаСтол(код, ждём.метка);

    const список = await спросить('/знакомые', { initData: подписьИгрока(зовущий, 'Аня') });
    const ключ = ((список.тело.знакомые || [])[0] || {}).ключ;
    проверить(!!ключ, ждём.игра + ': нет ключа знакомого');

    /* Чужая метка при живом столе: ссылка «зовёт» в другую игру, а стол —
       этой игры. И письмо знакомому, и приглашение за стол обязаны отказать. */
    const чужая = ОЖИДАНИЕ[(н + 1) % ОЖИДАНИЕ.length];
    const чужаяСсылка = ссылкаЗаСтол(код, чужая.метка);
    const доЧужого = журнал.length;
    const чужойЗов = await спросить('/позвать', { initData: подписьИгрока(зовущий, 'Аня'), ключ: ключ, ссылка: чужаяСсылка, код: код });
    проверить(чужойЗов.тело.ок === false, ждём.игра + ': /позвать с меткой «' + чужая.метка + '» за стол этой игры не отказал');
    проверить(!журнал.slice(доЧужого).some(function (з) { return з.метод === 'sendMessage'; }),
      ждём.игра + ': по ссылке с чужой меткой ушло письмо');
    проверить(сервера.сообщениеЗаСтол({ ссылка: чужаяСсылка }) === null,
      ждём.игра + ': приглашение за стол с меткой «' + чужая.метка + '» собрано для живого стола другой игры');
    проверить(сервера.сообщениеЗаСтол({ ссылка: ссылкаСНомером(код, чужая.метка, НОМЕР_ПРИГЛАШЕНИЯ) }) === null,
      ждём.игра + ': приглашение «метка_КОД_ИД» с чужой меткой собрано для живого стола');
    проверено.чужихМеток++;

    const былоПисем = журнал.length;
    const зов = await спросить('/позвать', { initData: подписьИгрока(зовущий, 'Аня'), ключ: ключ, ссылка: ссылка, код: код });
    проверить(зов.тело.ок === true, ждём.игра + ': /позвать отказал: ' + (зов.тело.причина || зов.код));
    const письмо = журнал.slice(былоПисем).find(function (з) {
      return з.метод === 'sendMessage' && Number(з.тело.chat_id) === друг;
    });
    проверить(!!письмо, ждём.игра + ': письмо знакомому не ушло');
    if (письмо) сверитьНазвание(письмо.тело.text, ждём, 'письмо знакомому по сети');

    const доПриглашения = журнал.length;
    const пр = await спросить('/приглашение', { initData: подписьИгрока(зовущий, 'Аня'), ссылка: ссылкаСНомером(код, ждём.метка, НОМЕР_ПРИГЛАШЕНИЯ) });
    проверить(пр.тело.ок === true, ждём.игра + ': /приглашение не подготовлено');
    const подготовка = журнал.slice(доПриглашения).find(function (з) { return з.метод === 'savePreparedInlineMessage'; });
    проверить(!!подготовка, ждём.игра + ': в Telegram не ушло подготовленное сообщение');
    if (подготовка) {
      const итог = подготовка.тело.result;
      сверитьНазвание(итог.input_message_content.message_text, ждём, 'приглашение за стол по сети');
      сверитьНазвание(итог.reply_markup.inline_keyboard[0][0].text, ждём, 'кнопка приглашения по сети');
    }
    if (код && ключ && письмо && подготовка) игрПрошло++;
  }
  проверить(игрПрошло === 8, 'по сети полностью прошло игр ' + игрПрошло + ' из 8');
  проверить(проверено.чужихМеток === 8, 'чужая метка проверена у ' + проверено.чужихМеток + ' игр из 8');
}

