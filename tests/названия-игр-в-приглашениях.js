/* =====================================================================
   НАЗВАНИЯ ИГР В ПРИГЛАШЕНИЯХ: у каждой из 8 сетевых игр — своё имя.

   Что проверяем (этап Э1 плана штаб/план-сыграть-с-другом.md). Раньше
   сервер знал только дурака и шашки: приглашение в нарды звучало как
   «Играем в подкидного дурака?», ссылка «nardy_КОД» не узнавалась
   вовсе («стол не тот»), лента бота называла деберц дураком. Теперь
   названия берутся из одной таблицы server/названия.js. Проверка:
     1. для каждой игры собирает ссылку за стол и разбирает её
        (разобратьСсылкуЗаСтол) — игра и код те же, что в ссылке;
        ссылка с номером приглашения «метка_КОД_ИД» (и прежний хвост
        «.id») даёт ту же игру и тот же код, startapp ≤ 64 знаков;
     2. письмо знакомому, сообщение «за стол» и три письма ленты
        называют ИМЕННО эту игру, и «дурака» в них нет, кроме дурака;
     3. таблица совпадает с реестром игр сервера и с метками js/сеть.js;
     4. через настоящий сервер на своём порту (по умолчанию 8801) и
        поддельный Telegram: /позвать и /приглашение для каждой игры
        проходят, и в ушедшем тексте — имя этой игры; ссылка с ЧУЖОЙ
        меткой на живой стол — отказ и в /позвать, и в приглашении за стол;
     5. слова «похвастаться победой» называют свою игру; перед «_» в
        ссылке годится только код стола (заглавные буквы и цифры, 4–12).

   Список ожиданий (метка и слово игры) записан ЗДЕСЬ, своими словами,
   а не взят из таблицы: иначе испорченная таблица сверялась бы сама
   с собой и проверка не покраснела бы.

   Запуск:
       node tests/названия-игр-в-приглашениях.js           (порт 8801)
       node tests/названия-игр-в-приглашениях.js 8805      (свой порт)
   Ломающий запуск — подсунуть испорченную КОПИЮ файла сервера:
       node tests/названия-игр-в-приглашениях.js --файл=ПУТЬ/названия.js
   Довод «--файл=» можно повторять; файл подменяет одноимённый файл из
   server/ при каждом require (сервер.js, лента.js, названия.js).
   Файлы проекта проверка не трогает. Данные — во временной папке.
   Выход 0 — провалов нет, 1 — есть.
   ===================================================================== */

