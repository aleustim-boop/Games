function ссылкаЗаСтол(код, метка) {
  return 'https://t.me/' + ИМЯ_БОТА + '/BoardGames?startapp=' + (метка ? метка + '_' : '') + код + '-' + АДРЕС_БУКВАМИ;
}

let проверок = 0;
const провалы = [];
function проверить(условие, что) {
  проверок++;
  if (!условие) {
    провалы.push(что);
    console.log('  ПРОВАЛ: ' + что);
  }
}

/** Есть ли в тексте слово игры и нет ли чужого «дурака». */
function сверитьНазвание(текст, ждём, где) {
  const нижний = String(текст || '').toLowerCase();
  проверить(нижний.indexOf(ждём.слово) !== -1,
    ждём.игра + ': в «' + где + '» нет названия игры («' + ждём.слово + '»): ' + текст);
  if (ждём.игра !== 'дурак') {
    проверить(нижний.indexOf('дурак') === -1,
      ждём.игра + ': в «' + где + '» стоит дурак вместо своей игры: ' + текст);
  }
}

/* ---------------------------------------------------------------------
   1–2. Чистые функции: разбор ссылки и слова писем
   --------------------------------------------------------------------- */

function проверитьСлова() {
  console.log('1. Разбор ссылки и слова писем для каждой игры');
  let игрПроверено = 0;
  for (const ждём of ОЖИДАНИЕ) {
    const код = 'K' + (игрПроверено + 1) + 'Z9';
    const стара = ссылкаЗаСтол(код, ждём.метка);
    const сНомером = ссылкаСНомером(код, ждём.метка, НОМЕР_ПРИГЛАШЕНИЯ);
    const сТочкой = стара + '.' + СТАРЫЙ_НОМЕР;
    const startapp = сНомером.split('startapp=')[1];
    проверить(startapp.length <= ПРЕДЕЛ_STARTAPP,
      ждём.игра + ': startapp с номером длиннее ' + ПРЕДЕЛ_STARTAPP + ' знаков (' + startapp.length + ')');

    const р1 = сервера.разобратьСсылкуЗаСтол(стара);
    проверить(!!р1, ждём.игра + ': ссылка без хвоста не разобралась');
    if (!р1) continue;
    проверить(р1.игра === ждём.игра, ждём.игра + ': ссылка «' + ждём.метка + '_» разобрана как «' + р1.игра + '»');
    проверить(р1.код === код, ждём.игра + ': код «' + р1.код + '», а ждали «' + код + '»');
    проверить(р1.хвост === АДРЕС_БУКВАМИ, ждём.игра + ': адрес в ссылке потерялся');
    проверить(р1.приглашение === '', ждём.игра + ': у ссылки без хвоста появился номер приглашения');

    const р2 = сервера.разобратьСсылкуЗаСтол(сНомером);
    проверить(!!р2, ждём.игра + ': ссылка «метка_КОД_ИД» не разобралась');
    if (р2) {
      проверить(р2.игра === р1.игра && р2.код === р1.код && р2.хвост === р1.хвост,
        ждём.игра + ': ссылка «метка_КОД_ИД» дала другую игру/код/адрес: ' + р2.игра + '/' + р2.код + '/' + р2.хвост);
      проверить(р2.приглашение === НОМЕР_ПРИГЛАШЕНИЯ, ждём.игра + ': номер приглашения из третьего поля не прочитан');
    }
    const р3 = сервера.разобратьСсылкуЗаСтол(сТочкой);
    проверить(!!р3 && р3.игра === р1.игра && р3.код === р1.код && р3.приглашение === СТАРЫЙ_НОМЕР,
      ждём.игра + ': прежний хвост «.id» перестал разбираться');

    сверитьНазвание(сервера.письмоЗнакомому('Аня', р1.игра, стара).текст, ждём, 'письмо знакомому');

    const сообщение = сервера.сообщениеЗаСтол({ ссылка: стара });
    проверить(!!сообщение, ждём.игра + ': сообщение «за стол» не собралось');
    if (сообщение) {
      сверитьНазвание(сообщение.текст, ждём, 'текст приглашения за стол');
      сверитьНазвание(сообщение.кнопка, ждём, 'кнопка приглашения за стол');
      проверить(сообщение.ссылка === стара, ждём.игра + ': кнопка ведёт не на присланную ссылку');
    }
    const сообщениеСНомером = сервера.сообщениеЗаСтол({ ссылка: сНомером });
    проверить(!!сообщениеСНомером, ждём.игра + ': ссылка с номером не годится для приглашения за стол');
    if (сообщениеСНомером) сверитьНазвание(сообщениеСНомером.текст, ждём, 'приглашение по ссылке с номером');

    for (const что of ['2', '3а', '3в']) {
      const письмо = лента.собратьПисьмо({ что: что, игра: р1.игра, ктоИмя: 'Боря', занятоМест: 2, всегоМест: 4 });
      проверить(!!письмо, ждём.игра + ': лента не собрала письмо «' + что + '»');
      if (письмо) сверитьНазвание(письмо.текст, ждём, 'лента, событие ' + что);
    }

    // «Похвастаться победой»: слова сервера называют свою игру, не дурака.
    for (const соперники of ['люди', 'боты']) {
      const описание = сервера.описаниеПобеды({ игра: ждём.игра, исход: 'победа', соперники: соперники, игроков: 2 });
      проверить(!!описание, ждём.игра + ': описание победы (' + соперники + ') не принято');
      if (!описание) continue;
      const слова = сервера.словаПобеды(описание);
      проверить(слова.toLowerCase().indexOf('победа ' + ждём.вПобеде + ' ') === 0,
        ждём.игра + ': слова победы (' + соперники + ') не «Победа ' + ждём.вПобеде + '»: ' + слова);
      if (ждём.игра !== 'дурак') {
        проверить(слова.toLowerCase().indexOf('дурак') === -1, ждём.игра + ': в словах победы стоит дурак: ' + слова);
      }
    }

    const наИгру = 'https://t.me/' + ИМЯ_БОТА + '/BoardGames?startapp=' + ждём.метка;
    проверить(сервера.этоНашаСсылкаНаИгру(наИгру), ждём.игра + ': ссылка на игру «' + ждём.метка + '» не признана нашей');
    проверить(сервера.играПоСсылке(наИгру) === ждём.игра,
      ждём.игра + ': ссылка на игру открывает «' + сервера.играПоСсылке(наИгру) + '»');
    игрПроверено++;
  }
  проверить(игрПроверено === 8, 'проверено игр ' + игрПроверено + ' из 8 — ноль или недобор это провал');

  // Старая ссылка дурака без метки — по-прежнему дурак.
  const безМетки = сервера.разобратьСсылкуЗаСтол(ссылкаЗаСтол('A1B2', ''));
  проверить(!!безМетки && безМетки.игра === 'дурак' && безМетки.код === 'A1B2', 'старая ссылка без метки перестала быть дураком');
  проверить(сервера.письмоЗнакомому('Аня', 'незнакомая', 'x').текст.indexOf('в подкидного дурака') !== -1,
    'незнакомая игра обязана читаться как дурак, а не пробрасывать чужое слово');

  // Кривой хвост «.id» — ссылка не наша.
  for (const кривой of ['.abc', '.ABCDEFGH', '.ab12cd34.ab12cd34', '.ab12cd345', '.']) {
    проверить(сервера.разобратьСсылкуЗаСтол(ссылкаЗаСтол('A1B2', 'nardy') + кривой) === null,
      'кривой хвост «' + кривой + '» принят за номер приглашения');
  }
  // Кривое третье поле — номером не считается, код не отрезается.
  for (const кривой of ['x', 'ab_cd', 'ab.cd', 'a'.repeat(17)]) {
    const р = сервера.разобратьСсылкуЗаСтол(ссылкаСНомером('A1B2', 'nardy', кривой));
    проверить(!р || (р.приглашение === '' && р.код !== 'A1B2'),
      'кривое третье поле «' + кривой + '» принято за номер приглашения');
  }
  // Дурак без метки: «КОД_ИД-адрес».
  const дуракСНомером = сервера.разобратьСсылкуЗаСтол(ссылкаСНомером('A1B2', '', НОМЕР_ПРИГЛАШЕНИЯ));
  проверить(!!дуракСНомером && дуракСНомером.игра === 'дурак' && дуракСНомером.код === 'A1B2' &&
    дуракСНомером.приглашение === НОМЕР_ПРИГЛАШЕНИЯ, 'ссылка дурака без метки «КОД_ИД» разобрана неверно');

  /* Перед «_» — только код стола (заглавные буквы и цифры, 4–12 знаков).
     Иначе номер не отрезается: «ab12_Ab12Cd34» — не стол ab12 с номером. */
  let кривыхКодов = 0;
  for (const кривойКод of ['ab12', 'A1b2', 'A1B', 'A1B2C3D4E5F6G', 'Щ1Б2']) {
    const р = сервера.разобратьСсылкуЗаСтол(ссылкаСНомером(кривойКод, 'nardy', НОМЕР_ПРИГЛАШЕНИЯ));
    проверить(!р || (р.приглашение === '' && р.код !== кривойКод),
      'код «' + кривойКод + '» перед «_» принят за код стола с номером приглашения');
    кривыхКодов++;
  }
  проверить(кривыхКодов === 5, 'кривых кодов проверено ' + кривыхКодов + ' из 5');
  const длинныйКод = сервера.разобратьСсылкуЗаСтол(ссылкаСНомером('A1B2C3D4E5F6', 'nardy', НОМЕР_ПРИГЛАШЕНИЯ));
  проверить(!!длинныйКод && длинныйКод.код === 'A1B2C3D4E5F6' && длинныйКод.приглашение === НОМЕР_ПРИГЛАШЕНИЯ,
    'код из 12 знаков перед «_» не разобран');

  // Слова победы дурака — буква в букву прежние (их же пишет js/game.js).
  проверить(сервера.словаПобеды({ игра: 'дурак', соперники: 'люди', игроков: 2, уровень: '' }) ===
    'Победа в подкидном дураке с другом. Сыграем?', 'слова победы дурака над людьми изменились');
  проверить(сервера.словаПобеды({ игра: 'дурак', соперники: 'боты', игроков: 3, уровень: 'сложный' }) ===
    'Победа в подкидном дураке над сложным ботом втроём. Сыграем?', 'слова победы дурака над ботами изменились');
}

/* ---------------------------------------------------------------------
   3. Таблица совпадает с реестром сервера и с метками браузера
   --------------------------------------------------------------------- */

function проверитьСогласие() {
  console.log('2. Таблица = реестр игр сервера = метки js/сеть.js');
  const изТаблицы = названия.сетевыеИгры().slice().sort().join(',');
  const изРеестра = реестр.всеИгры().slice().sort().join(',');
  проверить(изТаблицы === изРеестра, 'игры таблицы (' + изТаблицы + ') ≠ игры реестра (' + изРеестра + ')');

  const текстСети = fs.readFileSync(path.join(КОРЕНЬ, 'js', 'сеть.js'), 'utf8');
  const строка = текстСети.match(/const МЕТКИ_ИГР = \{([^}]*)\}/);
  проверить(!!строка, 'в js/сеть.js не нашлась строка МЕТКИ_ИГР');
  const пары = строка ? строка[1].match(/[a-z]+\s*:\s*'[^']+'/g) || [] : [];
  проверить(пары.length === 8, 'в МЕТКИ_ИГР js/сеть.js найдено меток: ' + пары.length + ', ждали 8');
  for (const пара of пары) {
    const [метка, игра] = пара.split(/\s*:\s*/);
    const слово = игра.replace(/'/g, '');
    проверить(названия.играПоМетке(метка) === слово,
      'метка «' + метка + '» у браузера — «' + слово + '», а у сервера — «' + названия.играПоМетке(метка) + '»');
  }
}

