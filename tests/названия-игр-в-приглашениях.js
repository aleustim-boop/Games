if (ПОДМЕНЫ.size) {
  const исходный = Module._resolveFilename;
  Module._resolveFilename = function (запрос, родитель, ...прочее) {
    /* Копия лежит во временной папке, а её require('./комнаты.js') должны
       находить соседей в server/ — подставляем родителю настоящий путь. */
    let кто = родитель;
    if (родитель && КОПИИ.has(родитель.filename)) {
      const настоящий = КОПИИ.get(родитель.filename);
      кто = Object.assign(Object.create(Object.getPrototypeOf(родитель)), родитель, {
        filename: настоящий, id: настоящий, paths: Module._nodeModulePaths(path.dirname(настоящий))
      });
    }
    const найдено = исходный.call(this, запрос, кто, ...прочее);
    return ПОДМЕНЫ.get(найдено) || найдено;
  };
  for (const [настоящий, копия] of ПОДМЕНЫ) {
    console.log('*** ЛОМАЮЩИЙ ЗАПУСК: вместо ' + path.relative(КОРЕНЬ, настоящий) + ' — копия ' + копия + ' ***');
  }
}

