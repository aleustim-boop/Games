/* =====================================================================
   «Хулиган»: проверка, что игра НЕ разрешает запрещённые ходы.

   На каждом шаге настоящей партии мы пробуем сделать что-нибудь
   незаконное — сходить не в свою очередь, побить туза шестёркой,
   подкинуть карту чужого достоинства, положить седьмую карту на стол —
   и убеждаемся, что игра отказала И состояние партии не изменилось.

   Запуск: node tests/попытки-нарушить-правила.js [сколько партий]
   ===================================================================== */

'use strict';

const игра = require(require('path').join(__dirname, '..', 'js', 'game.js'));

const ПАРТИЙ = Number(process.argv[2]) || 400;

/* Повторимая случайность: тот же номер партии — та же раздача.
   Генератор общий на все проверки и лежит отдельно (tests/общий-генератор.js).
   Прежняя самодельная копия теряла младшие разряды при умножении: она ходила
   по кругу всего из 11-16 тысяч чисел, а бросок «выбери одно из 36» был перекошен
   на треть. Из-за замены НОМЕРА ПАРТИЙ ИЗ ОТЧЁТОВ, СДЕЛАННЫХ РАНЬШЕ, больше
   не воспроизводятся: под тем же номером теперь другая раздача. */
const генератор = require(require('path').join(__dirname, 'общий-генератор.js'));
генератор.захватитьСлучайность();
генератор.поставитьЗерно(12345);

/** Полный слепок партии — с ним сравниваем, не изменилось ли что-то. */
function слепок(п) {
  const карта = (к) => к ? к.имя + к.масть : '—';
  return JSON.stringify({
    колода: п.колода.map(карта),
    человек: п.руки.человек.map(карта),
    бот: п.руки.бот.map(карта),
    стол: п.стол.map(пара => карта(пара.атака) + '/' + карта(пара.защита)),
    отбой: п.отбой.map(карта),
    атакует: п.атакует, берёт: п.берёт, завершена: п.завершена
  });
}

const беды = [];
function проверить(условие, текст, номер) {
  if (!условие) {
    const строка = 'партия ' + номер + ': ' + текст;
    if (беды.indexOf(строка) === -1 && беды.length < 12) беды.push(строка);
  }
}

let попыток = 0;

for (let н = 1; н <= ПАРТИЙ; н++) {
  генератор.поставитьЗерно((н * 6151 + 17) | 0);
  const п = игра.создатьПартию();
  let шагов = 0;

  while (!п.завершена && шагов++ < 400) {
    const ходит = игра.ктоХодит(п);
    const чужой = ходит === 'человек' ? 'бот' : 'человек';
    const фаза = игра.фаза(п);
    const до = слепок(п);

    // 1. Ход не в свою очередь.
    for (let i = 0; i < п.руки[чужой].length; i++) {
      попыток++;
      проверить(игра.положитьВАтаку(п, чужой, i) === false, 'разрешили сходить не в свою очередь', н);
    }
    проверить(слепок(п) === до, 'партия изменилась после попытки сходить не в свою очередь', н);

    // 2. Отбиться картой, которая не бьёт; отбить уже побитую пару; отбить не в фазе защиты.
    const защитник = игра.защищается(п);
    for (let iПары = 0; iПары < п.стол.length; iПары++) {
      const пара = п.стол[iПары];
      for (let i = 0; i < п.руки[защитник].length; i++) {
        const моя = п.руки[защитник][i];
        const законно = фаза === 'защита' && !пара.защита && игра.бьёт(моя, пара.атака, п.козырь);
        if (законно) continue;
        попыток++;
        проверить(игра.отбить(п, iПары, i) === false,
          'разрешили побить ' + пара.атака.имя + пара.атака.масть + ' картой ' + моя.имя + моя.масть +
          ' (козырь ' + п.козырь + ', фаза «' + фаза + '», пара уже побита: ' + (пара.защита ? 'да' : 'нет') + ')', н);
      }
      // Отбить пару с несуществующим номером карты
      попыток++;
      проверить(игра.отбить(п, iПары, 999) === false, 'разрешили отбиться несуществующей картой', н);
    }
    // Отбить несуществующую пару
    попыток++;
    проверить(игра.отбить(п, 99, 0) === false, 'разрешили отбить несуществующую карту на столе', н);
    проверить(слепок(п) === до, 'партия изменилась после запрещённых попыток отбиться', н);

    // 3. Подкинуть карту чужого достоинства и подкинуть седьмую карту.
    if (фаза === 'подкидывание' || фаза === 'докидывание') {
      const наСтоле = new Set();
      for (const пара of п.стол) {
        наСтоле.add(пара.атака.имя);
        if (пара.защита) наСтоле.add(пара.защита.имя);
      }
      for (let i = 0; i < п.руки[п.атакует].length; i++) {
        const моя = п.руки[п.атакует][i];
        if (наСтоле.has(моя.имя)) continue;
        попыток++;
        проверить(игра.можноПоложить(п, моя) === false, 'игра считает, что можно подкинуть ' + моя.имя + моя.масть +
          ', хотя на столе только ' + Array.from(наСтоле).join(','), н);
        проверить(игра.положитьВАтаку(п, п.атакует, i) === false, 'разрешили подкинуть ' + моя.имя + моя.масть +
          ' чужого достоинства (на столе ' + Array.from(наСтоле).join(',') + ')', н);
      }
    }
    if (п.стол.length >= 6) {
      for (let i = 0; i < п.руки[п.атакует].length; i++) {
        попыток++;
        проверить(игра.положитьВАтаку(п, п.атакует, i) === false, 'разрешили положить седьмую карту на стол', н);
      }
    }
    проверить(слепок(п) === до, 'партия изменилась после запрещённых попыток подкинуть', н);

    // 4. «Беру» не в фазе защиты.
    if (фаза !== 'защита') {
      попыток++;
      проверить(игра.объявитьБеру(п) === false, 'разрешили сказать «Беру» в фазе «' + фаза + '»', н);
      проверить(слепок(п) === до, 'партия изменилась после «Беру» не вовремя', н);
    }

    // Законный ход, чтобы партия двигалась дальше.
    const действие = игра.ходБота(п, ходит);
    проверить(действие !== 'не его ход', 'бот отказался ходить в свою очередь (фаза «' + фаза + '»)', н);
    проверить(слепок(п) !== до || п.завершена, 'законный ход «' + действие + '» ничего не изменил — партия стоит', н);
  }

  проверить(п.завершена, 'партия не закончилась за 400 ходов', н);
}

console.log('=== Попытки нарушить правила ===');
console.log('партий: ' + ПАРТИЙ + ', запрещённых попыток сделано: ' + попыток);
if (беды.length === 0) {
  console.log('игра не пропустила ни одного запрещённого хода');
  process.exit(0);
} else {
  console.log('ПРОПУЩЕНЫ НАРУШЕНИЯ:');
  беды.forEach(б => console.log('  - ' + б));
  process.exit(1);
}
