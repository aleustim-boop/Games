'use strict';

/* =====================================================================
   ПРОВЕРКА: мягкая надпись про пропажу друга (js/сеть.js, этап Э1 плана
   штаб/план-друг-пропал-со-связи.md).

   Что тут проверяется. Раньше пропажа друга сразу писала тревожный текст
   «Друг пропал со связи…». Короткая икота туннеля обычно проходит сама
   за секунды, и такая надпись пугала зря. Теперь первые МЯГКАЯ_ПРОПАЖА
   (20 секунд) после пропажи пишется спокойное «Друг переподключается…»,
   и только если друга всё ещё нет — прежнее тревожное.

   Проверяем четыре вещи:
     1) наружная константа window.Сеть.МЯГКАЯ_ПРОПАЖА равна 20000;
     2) чистая функция window.Сеть.текстПропажи(мс) возвращает нужный
        текст на границах (0, 19999, 20000, 60000) — сравнение дословное;
     3) в самом файле js/сеть.js ОЖИДАНИЕ_ОПРОСА правда 30 секунд, а не
        старые 40 (проверка по тексту файла, не по поведению);
     4) через настоящий разговор с сервером (поддельный fetch + поддельные
        часы): строка связи сперва мягкая, после 20 секунд молчания —
        тревожная, а когда друг находится — следующая пропажа снова
        начинается с мягкой надписи (момент пропажи обнулился).

   Как поднимаем js/сеть.js без браузера — как в tests/переспрос-при-
   сворачивании.js: песочница vm из tests/поддельный-браузер.js
   (поднять, сделатьДокумент, сделатьПамять), сеть подделываем сами.
   Внутренних имён (соперникПропалС, освежитьСтрокуСвязи, принятьСостояние)
   снаружи не видно — файл замкнут в (function(){...})(). До них дотягиваемся
   тем же путём, что и настоящий браузер: создаём комнату и отправляем ходы
   через window.Сеть.создатьКомнату/отправитьХод, а сервер подделываем так,
   чтобы он присылал нужное нам состояние соперника.

   Запуск:            node tests/мягкая-пропажа.js
   Ломающий запуск:    node tests/мягкая-пропажа.js --сломать
     — копирует js/сеть.js во временную папку (fs.mkdtempSync в os.tmpdir(),
       НЕ в проект), в копии текстПропажи всегда отдаёт тревожный текст,
       поднимает КОПИЮ. Пункт 2 обязан покраснеть. Строка для замены
       ищется дословно — не нашлась, значит сеть.js изменился и порчу
       надо переписать: скрипт в этом случае выходит с кодом 2, а не
       делает вид, что всё хорошо. Копию за собой прибираем.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { поднять, сделатьДокумент, сделатьПамять, поддельныеЧасы } = require('./поддельный-браузер.js');

const КОРЕНЬ = path.join(__dirname, '..');
const ПУТЬ_СЕТЬ = path.join(КОРЕНЬ, 'js', 'сеть.js');

const ломать = process.argv.indexOf('--сломать') !== -1;

/* ---------------------------------------------------------------------
   Путь из полного адреса запроса: «http://127.0.0.1:8790/что-нового» → «/что-нового».
   --------------------------------------------------------------------- */
function путьИзАдреса(url) {
  const м = String(url).match(/^https?:\/\/[^/]+(\/.*)$/);
  return м ? м[1] : String(url);
}

/* ---------------------------------------------------------------------
   Порча для --сломать: тело текстПропажи всегда отдаёт тревожный текст.
   Строка ищется дословно (взята прямо из файла) — не нашлась, значит
   разработчик поменял функцию, и порчу надо переписать заново.
   --------------------------------------------------------------------- */
function испортитьКопию(исходник) {
  // Файл в проекте хранится с переводом строки \r\n (Windows) — сверяемся
  // с настоящими символами файла, а не с тем, как их показывает редактор.
  const было =
    '  function текстПропажи(мсСПропажи) {\r\n' +
    '    return мсСПропажи < МЯГКАЯ_ПРОПАЖА\r\n' +
    '      ? ТЕКСТ_ДРУГ_ПЕРЕПОДКЛЮЧАЕТСЯ\r\n' +
    '      : ТЕКСТ_ДРУГ_ПРОПАЛ;\r\n' +
    '  }';
  const стало =
    '  function текстПропажи(мсСПропажи) {\r\n' +
    '    return ТЕКСТ_ДРУГ_ПРОПАЛ;   // испорчено проверкой --сломать\r\n' +
    '  }';
  if (исходник.indexOf(было) === -1) {
    console.error('Порча не удалась: тело текстПропажи не найдено дословно в js/сеть.js — ' +
      'функцию переписали, проверку --сломать надо обновить под новый текст.');
    process.exit(2);
  }
  return исходник.split(было).join(стало);
}

/* ---------------------------------------------------------------------
   Лёгкая песочница — только для чистых проверок 1 и 2 (без сети).
   --------------------------------------------------------------------- */
function поднятьЛёгкую(исходник) {
  return поднять(исходник, {
    документ: сделатьДокумент(),
    память: сделатьПамять(false),
    telegram: { onEvent: function () {}, offEvent: function () {}, isActive: true },
    fetch: function () {
      return Promise.resolve({ ok: true, status: 200, json: function () { return Promise.resolve({}); } });
    },
    размер: { ширина: 390, высота: 844 },
    имяФайла: 'js/сеть.js'
  });
}

/* ---------------------------------------------------------------------
   Состояние партии для поддельного сервера: минимальный набор полей,
   которых хватает принятьСостояние()/освежитьСтрокуСвязи(), чтобы не
   упасть и не задеть ветки, нас не интересующие.
   --------------------------------------------------------------------- */
function видПартии(соперникНаСвязи, номерСобытия) {
  return {
    версия: номерСобытия,
    этап: 'игра',
    завершена: false,
    яХожу: false,
    яХозяин: true,
    соперникНаСвязи: соперникНаСвязи,
    соперникУшёл: false,
    номерСобытия: номерСобытия
  };
}

/* ---------------------------------------------------------------------
   Пункт 4: настоящий разговор с поддельным сервером + поддельные часы.
   Возвращает { проверки, пропущен, причина }: если сценарий не удалось
   довести до конца, «пропущен» = true и честная причина, а не украшение.
   --------------------------------------------------------------------- */
function проверитьПункт4(исходникДляЗагрузки) {
  const проверки = [];
  const проверить = function (условие, текст) { проверки.push({ ок: Boolean(условие), текст: текст }); };

  const часы = поддельныеЧасы();
  const жСвязь = [];
  let следующийОтветНаХод = null;

  function fakeFetch(url, settings) {
    const путь = путьИзАдреса(url);
    if (путь === '/создать') {
      return Promise.resolve({
        ok: true, status: 200,
        json: function () {
          return Promise.resolve({ ок: true, код: 'AAAA', пропуск: 'ppp', состояние: видПартии(true, 1) });
        }
      });
    }
    if (путь === '/что-нового') {
      // Висит вечно — ровно как настоящий длинный опрос, до конца проверки
      // он нам не понадобится: состояние двигаем через /ход.
      return new Promise(function () {});
    }
    if (путь === '/ход') {
      const ответ = следующийОтветНаХод || { принято: true };
      следующийОтветНаХод = null;
      return Promise.resolve({ ok: true, status: 200, json: function () { return Promise.resolve(ответ); } });
    }
    return Promise.resolve({ ok: true, status: 200, json: function () { return Promise.resolve({}); } });
  }

  const рез = поднять(исходникДляЗагрузки, {
    документ: сделатьДокумент(),
    память: сделатьПамять(false),
    часы: часы,
    telegram: { onEvent: function () {}, offEvent: function () {}, isActive: true },
    fetch: fakeFetch,
    размер: { ширина: 390, высота: 844 },
    имяФайла: 'js/сеть.js'
  });

  рез.окно.ИграПоСети = {
    начать: function () {},
    экран: function () {},
    показатьВид: function () {},
    показатьСвязь: function (текст, вид) { жСвязь.push({ текст: текст, вид: вид }); }
  };

  const пауза = function (мс) { return new Promise(function (r) { setTimeout(r, мс || 0); }); };
  const последняяСтрока = function () { return жСвязь.length ? жСвязь[жСвязь.length - 1].текст : null; };

  return (async function () {
    try {
      // ---- Вход в комнату: друг сразу на связи ----
      const итогСоздания = await рез.спросить("window.Сеть.создатьКомнату({мест:2, переводной:false, парами:false})");
      if (!итогСоздания || итогСоздания.ок !== true) {
        return { проверки: проверки, пропущен: true,
          причина: 'поддельный /создать не принят игрой (итогСоздания.ок !== true) — до сценария не дошли' };
      }
      await пауза(10);

      // ---- Друг пропал: сразу должна появиться МЯГКАЯ надпись ----
      следующийОтветНаХод = { принято: true, состояние: видПартии(false, 2) };
      await рез.спросить('window.Сеть.отправитьХод({})');
      проверить(последняяСтрока() === 'Соперник переподключается…',
        'сразу после пропажи строка связи мягкая: «Соперник переподключается…» (получили: ' + JSON.stringify(последняяСтрока()) + ')');

      // ---- Двадцать секунд молчания ----
      часы.прошло(20000);
      следующийОтветНаХод = { принято: true, состояние: видПартии(false, 3) };
      await рез.спросить('window.Сеть.отправитьХод({})');
      проверить(последняяСтрока() === 'Соперник пропал со связи — ждём, партия сохранена',
        'через 20 секунд молчания строка связи тревожная (получили: ' + JSON.stringify(последняяСтрока()) + ')');

      // ---- Друг нашёлся: момент пропажи должен обнулиться ----
      следующийОтветНаХод = { принято: true, состояние: видПартии(true, 4) };
      await рез.спросить('window.Сеть.отправитьХод({})');

      // ---- Друг пропал снова, время часов не двигали: снова МЯГКАЯ надпись ----
      следующийОтветНаХод = { принято: true, состояние: видПартии(false, 5) };
      await рез.спросить('window.Сеть.отправитьХод({})');
      проверить(последняяСтрока() === 'Соперник переподключается…',
        'после того как друг нашёлся, следующая пропажа снова начинается с мягкой надписи ' +
        '(момент пропажи обнулился; получили: ' + JSON.stringify(последняяСтрока()) + ')');

      проверить(рез.ошибкиКонсоли.length === 0,
        'за сценарий пункта 4 в консоли песочницы нет ошибок' +
        (рез.ошибкиКонсоли.length ? ': ' + рез.ошибкиКонсоли.join(' | ') : ''));

      return { проверки: проверки, пропущен: false };
    } catch (сбой) {
      return { проверки: проверки, пропущен: true,
        причина: 'сценарий упал с ошибкой: ' + (сбой && сбой.stack || сбой) };
    }
  })();
}

/* ---------------------------------------------------------------------
   Основной прогон
   --------------------------------------------------------------------- */
function запуститьПроверку() {
  return (async function () {
    const проверки = [];
    const проверить = function (условие, текст) { проверки.push({ ок: Boolean(условие), текст: текст }); };

    const исходникРеальный = fs.readFileSync(ПУТЬ_СЕТЬ, 'utf8');

    let путьЗагрузки = ПУТЬ_СЕТЬ;
    let исходникДляЗагрузки = исходникРеальный;
    let временнаяПапка = null;
    if (ломать) {
      // Сперва считаем испорченный текст (испортитьКопию сама завершит
      // процесс кодом 2, если строка для порчи не найдена) — и только
      // при успехе заводим временную папку, чтобы не оставлять мусор
      // в TEMP при неудачной порче.
      исходникДляЗагрузки = испортитьКопию(исходникРеальный);
      временнаяПапка = fs.mkdtempSync(path.join(os.tmpdir(), 'мягкая-пропажа-'));
      путьЗагрузки = path.join(временнаяПапка, 'сеть.js');
      fs.writeFileSync(путьЗагрузки, исходникДляЗагрузки, 'utf8');
    }

    try {
      // ---- Пункт 1: наружная константа ----
      const лёгкая = поднятьЛёгкую(исходникДляЗагрузки);
      проверить(лёгкая.окно.Сеть && лёгкая.окно.Сеть.МЯГКАЯ_ПРОПАЖА === 20000,
        'пункт 1: window.Сеть.МЯГКАЯ_ПРОПАЖА === 20000 (получили: ' +
        (лёгкая.окно.Сеть ? лёгкая.окно.Сеть.МЯГКАЯ_ПРОПАЖА : 'window.Сеть нет') + ')');

      // ---- Пункт 2: чистая функция текстПропажи на границах ----
      const текстПропажи = лёгкая.окно.Сеть && лёгкая.окно.Сеть.текстПропажи;
      if (typeof текстПропажи !== 'function') {
        проверить(false, 'пункт 2: window.Сеть.текстПропажи не функция — остальные проверки пункта 2 пропущены');
      } else {
        проверить(текстПропажи(0) === 'Соперник переподключается…',
          'пункт 2: текстПропажи(0) === «Соперник переподключается…» (получили: ' + JSON.stringify(текстПропажи(0)) + ')');
        проверить(текстПропажи(19999) === 'Соперник переподключается…',
          'пункт 2: текстПропажи(19999) === «Соперник переподключается…» (получили: ' + JSON.stringify(текстПропажи(19999)) + ')');
        проверить(текстПропажи(20000) === 'Соперник пропал со связи — ждём, партия сохранена',
          'пункт 2: текстПропажи(20000) === «Соперник пропал со связи — ждём, партия сохранена» (получили: ' + JSON.stringify(текстПропажи(20000)) + ')');
        проверить(текстПропажи(60000) === 'Соперник пропал со связи — ждём, партия сохранена',
          'пункт 2: текстПропажи(60000) === «Соперник пропал со связи — ждём, партия сохранена» (получили: ' + JSON.stringify(текстПропажи(60000)) + ')');
      }

      // ---- Пункт 3: текст файла (всегда настоящего, не подмены) ----
      const совпаденияНовое = исходникРеальный.match(/const\s+ОЖИДАНИЕ_ОПРОСА\s*=\s*30\s*\*\s*1000\s*;/g) || [];
      проверить(совпаденияНовое.length === 1,
        'пункт 3: «const ОЖИДАНИЕ_ОПРОСА = 30 * 1000» встречается ровно один раз (нашли: ' + совпаденияНовое.length + ')');
      const совпаденияСтарое = исходникРеальный.match(/ОЖИДАНИЕ_ОПРОСА\s*=\s*40\s*\*\s*1000/g) || [];
      проверить(совпаденияСтарое.length === 0,
        'пункт 3: старого «ОЖИДАНИЕ_ОПРОСА = 40 * 1000» рядом нет (нашли: ' + совпаденияСтарое.length + ')');

      // ---- Пункт 4: настоящий разговор через поддельный сервер ----
      const итог4 = await проверитьПункт4(исходникДляЗагрузки);
      if (итог4.пропущен) {
        console.log('Пункт 4 проверить не удалось: ' + итог4.причина);
        проверить(false, 'пункт 4: сценарий строки связи через поддельный сервер (' + итог4.причина + ')');
      } else {
        for (const п of итог4.проверки) проверки.push(п);
      }

      const провалы = проверки.filter(function (п) { return !п.ок; });
      console.log((ломать ? '[--сломать] ' : '') + 'Мягкая пропажа со связи:');
      for (const п of проверки) console.log((п.ок ? '  ok   ' : '  ПРОВАЛ ') + п.текст);
      console.log('Итого проверок: ' + проверки.length + ', провалов: ' + провалы.length);
      /* Пункт 4 внутри поднимает настоящий часовойСвязи (setInterval,
         реальную 1 секунду) и часовойВладения, а /что-нового у нас висит
         вечно — сами по себе они никогда не отпустят процесс. Прибираем
         временную папку и завершаемся явно, а не через exitCode. */
      if (временнаяПапка) {
        try { fs.rmSync(временнаяПапка, { recursive: true, force: true }); }
        catch (e) { console.error('Не удалось убрать временную папку ' + временнаяПапка + ': ' + e); }
      }
      process.exit(провалы.length ? 1 : 0);
    } catch (сбойСнаружи) {
      console.error('Проверка упала с ошибкой: ' + (сбойСнаружи && сбойСнаружи.stack || сбойСнаружи));
      if (временнаяПапка) {
        try { fs.rmSync(временнаяПапка, { recursive: true, force: true }); } catch (e) {}
      }
      process.exit(1);
    }
  })();
}

