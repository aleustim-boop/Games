раздел('9', 'Стол с человеком: режиссёр отпускает');
let меткаГостя = 0;

/** Открыть столы, посадить человека за стол шашек (партия раздаётся сразу). */
function посадитьЧеловекаЗаСтолШашек() {
  запуститьЧисто();
  шагатьПодряд(6, НАЧАЛО, 7000);
  const стол = режиссёр.моиСтолы().find(function (с) { return с.игра === 'шашки'; });
  if (!стол) return null;
  меткаГостя++;
  const вход = комнаты.войтиВКомнату(стол.код, { имя: 'Гость', метка: 'метка-живых-лобби-' + меткаГостя });
  return { стол: стол, вход: вход };
}

/** Один сценарий: после посадки человека часы уходят за срок стола, дальше — условия сценария. */
function сценарийСЧеловеком(название, условия, ждатьЗамену) {
  const посадка = посадитьЧеловекаЗаСтолШашек();
  проверить(!!посадка, название + ': среди столов режиссёра нет стола шашек');
  if (!посадка) return;
  const код = посадка.стол.код;
  проверить(посадка.вход && посадка.вход.ок === true, название + ': человек не сел за стол режиссёра по коду');
  проверить(комнаты.состояниеСтола(код).людей === 1, название + ': комнаты не видят человека за столом');
  const личныеСтолаСЧеловеком = посадка.стол.личины.slice();

  условия();
  const сдвиг = НАЧАЛО + 13 * МИНУТА;   // дольше самого длинного срока стола (12 минут)
  const итог = режиссёр.шаг(сдвиг);
  проверить(!!итог, название + ': шаг режиссёра ничего не вернул');
  проверить(комнаты.состояниеСтола(код).есть && комнаты.состояниеСтола(код).людей === 1,
    название + ': стол с человеком закрыт или пуст');
  проверить(!режиссёр.моиСтолы().some(function (с) { return с.код === код; }),
    название + ': режиссёр не отпустил стол с человеком');

  if (ждатьЗамену) {
    // Через паузу после ротации у шашек снова ровно один ожидающий стол — новый.
    шагатьПодряд(40, сдвиг + 7000, 7000);
    const шашки = режиссёр.моиСтолы().filter(function (с) { return с.игра === 'шашки'; });
    проверить(шашки.length === 1 && шашки[0].код !== код,
      название + ': игре не открыта замена: ожидающих столов шашек ' + шашки.length);
    // Личины из партии с человеком заняты: второй раз за стол режиссёра не сядут.
    for (const стол of режиссёр.моиСтолы()) {
      for (const номер of стол.личины) {
        проверить(!личныеСтолаСЧеловеком.includes(номер),
          название + ': за новым столом сидит личина из партии с человеком (№' + номер + ')');
      }
    }
    проверить(комнаты.состояниеСтола(код).есть, название + ': после замены стол с человеком пропал');
  }
}

