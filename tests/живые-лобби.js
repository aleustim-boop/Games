/** Несколько шагов подряд с ходом часов; возвращает последнее время. */
function шагатьПодряд(сколько, с, шагМс) {
  let время = с;
  for (let i = 0; i < сколько; i++) {
    режиссёр.шаг(время);
    время += шагМс;
  }
  return время;
}

function столовИгры(игра) {
  return режиссёр.моиСтолы().filter(function (с) { return с.игра === игра; }).length;
}

function личныеНомера() {
  const все = [];
  for (const стол of режиссёр.моиСтолы()) for (const н of стол.личины) все.push(н);
  return все;
}

