раздел('12', 'Человек сел за стол с прихожей и ушёл: режиссёр подхватывает стол');
{
  очистить();
  const столовВКомнатахДо = комнаты.сколькоСтоловЛичин();   // чужие столы личин (из раздела 9)
  запуститьЧисто();
  шагатьПодряд(6, НАЧАЛО, 7000);
  const стол = режиссёр.моиСтолы().find(function (с) { return с.игра === 'катан'; });
  проверить(!!стол, 'среди столов режиссёра нет стола катана (прихожая на 3 места)');
  if (стол) {
    меткаГостя++;
    const вход = комнаты.войтиВКомнату(стол.код, { имя: 'Гость', метка: 'метка-живых-лобби-' + меткаГостя });
    проверить(вход.ок === true && комнаты.состояниеСтола(стол.код).людей === 1 &&
      комнаты.состояниеСтола(стол.код).этап === 'ожидание', 'человек не сел в прихожую стола катана');

    // Шаг при человеке: стол отпущен, катану открывается замена.
    режиссёр.шаг(НАЧАЛО + 50000);
    проверить(!режиссёр.моиСтолы().some(function (с) { return с.код === стол.код; }),
      'стол с человеком в прихожей не отпущен');

    // Человек уходит из прихожей: стол остаётся «ждёт гостей» (комнаты его не убирают).
    const найденный = комнаты.найтиИгрока(стол.код, вход.пропуск);
    проверить(!!найденный, 'не нашли сидящего человека по пропуску');
    if (найденный) комнаты.выйти(найденный.комната, найденный.ктоЯ, false);
    const после = комнаты.состояниеСтола(стол.код);
    проверить(после.есть && после.людей === 0, 'после ухода стол должен остаться пустым и живым в комнатах');

    // Шаги: режиссёр подхватил стол; лишний (сверх цели) закрыт — «висячих» столов нет.
    шагатьПодряд(3, НАЧАЛО + 57000, 7000);
    const мои = режиссёр.моиСтолы();
    проверить(комнаты.сколькоСтоловЛичин() - столовВКомнатахДо === мои.length,
      'в комнатах столов личин ' + (комнаты.сколькоСтоловЛичин() - столовВКомнатахДо) +
      ', а режиссёр ведёт ' + мои.length + ': лишний стол висит без присмотра');
    проверить(мои.filter(function (с) { return с.игра === 'катан'; }).length === 1,
      'столов катана у режиссёра не один: ' + мои.filter(function (с) { return с.игра === 'катан'; }).length);
    const номера = личныеНомера();
    проверить(new Set(номера).size === номера.length, 'после подхвата личина за двумя столами');
  }
  очистить();
}

