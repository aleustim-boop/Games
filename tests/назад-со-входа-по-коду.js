/* =====================================================================
   ПРОВЕРКА: «НАЗАД» СО ВХОДА ПО КОДУ ВОЗВРАЩАЕТ В ЛОББИ (ШАШКИ, НАРДЫ).

   Поломка была такой: на лобби нажать «Есть код? Войти» (#лобби-код) —
   открывается #экран-входа. Нажать там «Назад» (#кнопка-вход-назад) —
   js/сеть.js (назадСоВхода, ~строка 4211) спрашивает у моста игры
   мост.назадСоВхода(); не найдя такой двери у шашек/нард, шёл запасным
   путём — открытьЭкранДруга() — и человек попадал на старый экран
   «Игра с другом» (#экран-друга), из которого пути в новое лобби нет.

   Починка (не в этом файле): js/шашки-сеть.js и js/нарды-сеть.js теперь
   отдают window.ИграПоСети.назадСоВхода — она ведёт туда же, куда и
   «В меню» (js/*-сеть.js, вМеню): в лобби.

   Запуск (стенд заранее поднят, например tests/локальный-сервер.js 8080):
       node tests/назад-со-входа-по-коду.js          порт 8080
       node tests/назад-со-входа-по-коду.js 8797     другой порт

   Ломающий запуск (обязан покраснеть — портит КОПИИ js/шашки-сеть.js
   и js/нарды-сеть.js во временной папке ОС: убирает из них регистрацию
   «назадСоВхода», снова включая запасной путь js/сеть.js. Файлы проекта
   не трогает и не откатывает — раздаёт с подменой на своей раздаче
   на свободном порту, файл проекта читает лишь для копирования):
       node tests/назад-со-входа-по-коду.js --сломать

   Написано тестировщиком, живёт в tests/, игру не трогает.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const os = require('os');
const http = require('http');
const { chromium, безTelegram } = require('./браузер-робот.js');

const КОРЕНЬ = path.join(__dirname, '..');
const СЛОМАТЬ = process.argv.includes('--сломать');
// Первый числовой аргумент — порт готового стенда (обычный прогон).
const ПОРТ_СТЕНДА = Number(process.argv.find((а) => /^\d+$/.test(а))) || 8080;

let всегоПроверок = 0;
let провалов = 0;
function проверить(условие, слова) {
  всегоПроверок++;
  if (условие) console.log('  ок   — ' + слова);
  else { провалов++; console.log('  ПЛОХО— ' + слова); }
}

const ТИПЫ = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.mp3': 'audio/mpeg'
};

/** Раздача файлов проекта на свободном порту — для ломающего запуска: без
 *  подмен читает КОРЕНЬ как есть, с подменами отдаёт вместо перечисленных
 *  путей файлы с диска (испорченные копии во временной папке). */
function поднятьРаздачу(подмены) {
  const карта = подмены || {};
  const сервер = http.createServer(function (запрос, ответ) {
    let путь = запрос.url.split('?')[0].split('#')[0];
    try { путь = decodeURIComponent(путь); } catch (ошибка) { /* оставим как есть */ }
    const файл = карта[путь] || path.join(КОРЕНЬ, путь.slice(1));
    fs.readFile(файл, function (беда, тело) {
      if (беда) { ответ.writeHead(404); ответ.end('нет такого файла'); return; }
      ответ.writeHead(200, { 'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'text/plain' });
      ответ.end(тело);
    });
  });
  return new Promise((готово) => сервер.listen(0, '127.0.0.1', () => готово(сервер)));
}

/* ---------------------------------------------------------------------
   ЛОМАЮЩИЙ ЗАПУСК --сломать: портим КОПИЮ моста (js/шашки-сеть.js или
   js/нарды-сеть.js) во временной папке — убираем из объекта
   window.ИграПоСети регистрацию «назадСоВхода», снова включая запасной
   путь js/сеть.js (открытьЭкранДруга). Файл проекта не трогаем.
   --------------------------------------------------------------------- */
function приготовитьИспорченныйМост(имяФайла) {
  const путьКФайлу = path.join(КОРЕНЬ, 'js', имяФайла);
  const исходник = fs.readFileSync(путьКФайлу, 'utf8');
  // Файл может лежать с \r\n — ищем регуляркой, а не строкой один-в-один.
  const образецБыло = /\r?\n {4}назадСоВхода: назадСоВхода,/;
  if (!образецБыло.test(исходник)) {
    console.error('ломающий запуск --сломать сломался: в js/' + имяФайла + ' не нашлась строка ' +
      'регистрации «назадСоВхода» в ожидаемом виде — ноль замен, портить нечего (провал, а не пропуск)');
    process.exit(2);
  }
  const испорченный = исходник.replace(образецБыло, '');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'назад-со-входа-'));
  const копия = path.join(папка, имяФайла);
  fs.writeFileSync(копия, испорченный, 'utf8');
  console.log('ломающий запуск --сломать: испорченная копия ' + имяФайла + ' лежит в ' + копия);
  return { копия, папка };
}

/** Экран с этим id виден (класс «экран--виден»)? Ждём с опросом, не бросаем. */
async function дождатьсяЭкрана(страница, id, мс) {
  try {
    await страница.waitForFunction(function (и) {
      const э = document.getElementById(и);
      return Boolean(э && э.classList.contains('экран--виден'));
    }, id, { timeout: мс || 4000 });
    return true;
  } catch (сбой) {
    return false;
  }
}

/** Слушатели ошибок страницы — не считаем шум от заблокированных нами же запросов. */
function собратьОшибки(страница) {
  const ошибки = [];
  страница.on('pageerror', (о) => ошибки.push('исключение: ' + о.message));
  страница.on('console', (с) => {
    if (с.type() === 'error' && /Failed to load resource/.test(с.text())) return;
    if (с.type() === 'error') ошибки.push('консоль: ' + с.text());
  });
  return ошибки;
}

/**
 * Сам сценарий поломки: лобби → «Есть код? Войти» → «Назад» →
 * ожидаем снова лобби, а не старый «Игра с другом».
 */
async function проверитьВозвратВЛобби(браузер, адрес, названиеИгры) {
  console.log('\n=== ' + названиеИгры + ': лобби → «Есть код? Войти» → «Назад» → снова лобби ===');
  const окно = await браузер.newContext({ viewport: { width: 390, height: 844 } });
  const страница = await окно.newPage();
  const ошибки = собратьОшибки(страница);
  await безTelegram(страница);
  await страница.goto(адрес);
  await страница.waitForTimeout(400);

  const стартовыйЭкран = await дождатьсяЭкрана(страница, 'экран-лобби', 3000);
  проверить(стартовыйЭкран, названиеИгры + ': страница открылась на #экран-лобби');

  await страница.click('#лобби-код');
  const входОткрылся = await дождатьсяЭкрана(страница, 'экран-входа', 3000);
  проверить(входОткрылся, названиеИгры + ': «Есть код? Войти» открыл #экран-входа');

  // «Назад» верхней строки самого экрана входа спрятана в некоторых
  // подделках Telegram — жмём узел напрямую по id, как это делают
  // другие проверки (tests/лобби-нард.js) для скрытых кнопок «‹».
  await страница.evaluate(() => {
    const к = document.getElementById('кнопка-вход-назад');
    if (к) к.click();
  });
  await страница.waitForTimeout(400);

  const вид = await страница.evaluate(() => ({
    лоббиВиден: Boolean(document.getElementById('экран-лобби')?.classList.contains('экран--виден')),
    другаВиден: Boolean(document.getElementById('экран-друга')?.classList.contains('экран--виден')),
    входаВиден: Boolean(document.getElementById('экран-входа')?.classList.contains('экран--виден'))
  }));
  console.log('  после «Назад»: ' + JSON.stringify(вид));
  проверить(вид.лоббиВиден, названиеИгры + ': после «Назад» со входа по коду снова видно #экран-лобби');
  проверить(!вид.другаВиден, названиеИгры + ': #экран-друга НЕ показан (старый тупиковый экран)');
  проверить(!вид.входаВиден, названиеИгры + ': #экран-входа больше не виден');

  проверить(ошибки.length === 0, названиеИгры + ': красных ошибок в консоли нет' +
    (ошибки.length ? ' — а они есть: ' + ошибки.join(' | ') : ''));

  await окно.close();
}

(async () => {
  let раздача = null;
  let адресШашек, адресНард;
  const испорченныеФайлы = [];

  if (СЛОМАТЬ) {
    const шашкиМост = приготовитьИспорченныйМост('шашки-сеть.js');
    const нардыМост = приготовитьИспорченныйМост('нарды-сеть.js');
    испорченныеФайлы.push(шашкиМост, нардыМост);
    раздача = await поднятьРаздачу({
      '/js/шашки-сеть.js': шашкиМост.копия,
      '/js/нарды-сеть.js': нардыМост.копия
    });
    const порт = раздача.address().port;
    адресШашек = 'http://127.0.0.1:' + порт + '/шашки.html';
    адресНард = 'http://127.0.0.1:' + порт + '/нарды.html';
    console.log('раздача поднята (ЛОМАЮЩИЙ ЗАПУСК --сломать): порт ' + порт);
  } else {
    адресШашек = 'http://127.0.0.1:' + ПОРТ_СТЕНДА + '/шашки.html';
    адресНард = 'http://127.0.0.1:' + ПОРТ_СТЕНДА + '/нарды.html';
    console.log('используем готовый стенд: http://127.0.0.1:' + ПОРТ_СТЕНДА + '/');
  }

  const браузер = await chromium.launch();

  await проверитьВозвратВЛобби(браузер, адресШашек, 'Шашки');
  await проверитьВозвратВЛобби(браузер, адресНард, 'Нарды');

  await браузер.close();
  if (раздача) раздача.close();
  for (const испорченный of испорченныеФайлы) {
    try { fs.unlinkSync(испорченный.копия); } catch (е) { /* уже нет — и ладно */ }
    try { fs.rmdirSync(испорченный.папка); } catch (е) { /* уже нет — и ладно */ }
  }

  console.log('\nИтого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
  process.exit(провалов === 0 ? 0 : 1);
})().catch((ошибка) => { console.error('проверка сломалась:', ошибка); process.exit(2); });
