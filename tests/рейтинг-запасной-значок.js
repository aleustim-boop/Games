'use strict';

/* =====================================================================
   ЗАПАСНОЙ ЗНАЧОК ИГРЫ НА КНОПКЕ ВЫБОРА В РЕЙТИНГЕ.

   Зачем этот файл. У домино и морского боя нет файлов img/рейтинг/
   домино.png и img/рейтинг/морской-бой.png (и их @2x) — раньше кнопка
   выбора игры («значокВыбраннойИгры» в js/рейтинг-экран.js) рисовала
   для них битую картинку. Теперь при ошибке загрузки <img> заменяется
   запасным кружком с первой буквой игры (класс «рейтинг-выбор-игры__
   значок--запаска» из style.css, тем же приёмом, что у профиля).

   Стенд уже поднят снаружи: http://127.0.0.1:8080/ — свой сервер здесь
   не поднимаем (файлов проекта отдаёт постоянный стенд как есть, значки
   домино и морского боя там правда отсутствуют — проверено curl'ом
   404). Дверь /рейтинг подделана прямо в браузере (выдуманный адрес
   сервера, тот же приём, что в tests/браузер-рейтинг-круг-друзей.js
   и tests/браузер-фото-в-рейтинге.js) — на боевой сервер комнат 8790
   игра вообще не стучится.

   ПУТЬ: открываем рейтинг «Дурака» (у него значок есть — проверяем
   заодно, что обычные игры запаску не получают), настоящим кликом
   открываем панель выбора игры, настоящим кликом выбираем «Домино»,
   ждём, пока браузер решит судьбу картинки, проверяем; то же для
   «Морской бой».

   ПРОВЕРКИ на каждую игру:
     — на всей странице нет ни одной <img> с complete=true и
       naturalWidth=0 (ноль — честный признак битой картинки, не
       пропуск: правило штаба «ноль найденного — провал», здесь
       наоборот — «непустой список битых — провал»);
     — на кнопке выбора игры нашёлся запасной кружок
       (.рейтинг-выбор-игры__значок--запаска) с первой буквой подписи.
   И контрольная проверка на «Дураке» (у него картинка есть): запаски
   на кнопке НЕТ, обычный <img> загрузился (naturalWidth > 0).

   ЗАПУСК
       node tests/рейтинг-запасной-значок.js
   Перед запуском — node штаб/браузер-занят.js --ждать (браузер на
   машине один, второй параллельно не открывать).

   ЛОМАЮЩИЙ ЗАПУСК (проверка обязана покраснеть)
       node tests/рейтинг-запасной-значок.js --копия=<путь к файлу>
   «--копия» не трогает ни один файл проекта: путь указывает на КОПИЮ
   js/рейтинг-экран.js, испорченную во временной папке ВНЕ проекта
   (например без обработчика ошибки у <img> — как было до правки).
   Страницы по-прежнему идут с настоящего стенда localhost:8080, но
   ЭТОТ ОДИН файл подменяется содержимым копии через page.route —
   настоящий js/рейтинг-экран.js на диске не трогается ни на секунду.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const { chromium, подготовитьПодделку, перехватить } = require('./браузер-робот.js');

const АДРЕС_СТРАНИЦЫ = 'http://127.0.0.1:8080/index.html';
// Дверь /рейтинг никуда по-настоящему не стучится — адрес сервера
// выдуманный, тот же приём, что в tests/браузер-фото-в-рейтинге.js.
const АДРЕС_СЕРВЕРА_ВЫДУМАННЫЙ = 'http://127.0.0.1:9';

const доводКопии = process.argv.find((д) => д.indexOf('--копия=') === 0);
const ПУТЬ_КОПИИ = доводКопии ? path.resolve(доводКопии.slice('--копия='.length)) : null;

let всегоПроверок = 0;
let провалов = 0;
function проверить(имя, годно, детали) {
  всегоПроверок += 1;
  console.log('  ' + (годно ? 'ок    — ' : 'ПЛОХО — ') + имя + (детали ? ' (' + детали + ')' : ''));
  if (!годно) провалов += 1;
}

function ответРейтинга(игра) {
  return { ок: true, узналиВас: false, игра: игра, всего: 0, яВТаблице: false, верхушка: [], вокругМеня: [] };
}

/** Дождаться, пока браузер решит судьбу картинок на кнопке выбора игры:
    либо появился запасной кружок, либо <img> долистал до complete. */
async function дождатьсяРешенияПоЗначку(страница) {
  await страница.waitForFunction(function () {
    const кнопка = document.getElementById('рейтинг-выбор-игры-кнопка');
    if (!кнопка) return false;
    if (кнопка.querySelector('.рейтинг-выбор-игры__значок--запаска')) return true;
    const img = кнопка.querySelector('img');
    return Boolean(img) && img.complete;
  }, { timeout: 8000 }).catch(() => { /* соберём то, что есть, — проверки сами покажут беду */ });
  // Небольшой запас: событие «error» у <img> в некоторых браузерах
  // приходит через микротик ПОСЛЕ «complete» — без паузы можно поймать
  // окно, где img.complete уже true, а запаска ещё не подставлена.
  await страница.waitForTimeout(150);
}

/** Все <img> на странице, у которых браузер точно решил (complete=true)
    и результат — битая картинка (naturalWidth=0). Непустой список —
    провал (не пропуск): именно это и есть «битая картинка» на экране. */
async function битыеКартинки(страница) {
  return страница.evaluate(function () {
    return Array.prototype.slice.call(document.querySelectorAll('img'))
      .filter(function (img) { return img.complete && img.naturalWidth === 0; })
      .map(function (img) { return img.src; });
  });
}

async function значокНаКнопке(страница) {
  return страница.evaluate(function () {
    const кнопка = document.getElementById('рейтинг-выбор-игры-кнопка');
    if (!кнопка) return { естьКнопка: false };
    const запаска = кнопка.querySelector('.рейтинг-выбор-игры__значок--запаска');
    const img = кнопка.querySelector('img');
    return {
      естьКнопка: true,
      естьЗапаска: Boolean(запаска),
      текстЗапаски: запаска ? запаска.textContent : null,
      естьImg: Boolean(img),
      naturalWidth: img ? img.naturalWidth : null,
      complete: img ? img.complete : null
    };
  });
}

async function выбратьИгруВПанели(страница, ключ) {
  await страница.click('#рейтинг-выбор-игры-кнопка', { timeout: 8000 });
  await страница.waitForSelector('#рейтинг-панель-игр:not(.скрыт)', { timeout: 8000 });
  const пункт = '#рейтинг-панель-игр-пункт-' + ключ;
  await страница.waitForSelector(пункт, { timeout: 8000 });
  await страница.click(пункт, { timeout: 8000 });
}

async function запуститьПрогон() {
  const браузер = await chromium.launch();
  const контекст = await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
  const страница = await контекст.newPage();

  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const текст = м.text();
    const откудаСырое = (м.location && м.location() && м.location().url) || '';
    let откуда = откудаСырое;
    try { откуда = decodeURIComponent(откудаСырое); } catch (о) { /* оставим как есть */ }
    if (/telegram-web-app\.js|telegram\.org/.test(текст + ' ' + откуда)) return;
    // Ожидаемый шум: браузер сам пишет «Failed to load resource: 404»
    // на несуществующие картинки домино и морского боя — это то самое,
    // что мы просили, не поломка.
    if (/Failed to load resource/.test(текст) && /\/img\/рейтинг\//.test(откуда)) return;
    красные.push('консоль: ' + текст + (откуда ? ' (' + откуда + ')' : ''));
  });

  await подготовитьПодделку(страница, { версия: '8.0' });

  // Дверь /рейтинг — подделана, реальных данных не просим (нам важна
  // только кнопка выбора игры, не таблица).
  await перехватить(страница, /\/рейтинг(?:\?|$)/, function (путь, запрос, адрес) {
    let игра = 'дурак';
    try {
      const тело = JSON.parse((запрос.postData && запрос.postData()) || '{}');
      if (тело && тело.игра) игра = тело.игра;
    } catch (о) { /* тела может не быть */ }
    путь.fulfill({ status: 200, contentType: 'application/json; charset=utf-8', body: JSON.stringify(ответРейтинга(игра)) });
  });

  // Ломающий режим: этот ОДИН файл подменяем содержимым испорченной
  // копии (путь пришёл доводом «--копия=»). Регистрируем ПОСЛЕ
  // «перехватить» выше — playwright отдаёт запрос последнему
  // зарегистрированному подходящему правилу (см. комментарий в
  // tests/браузер-робот.js), значит этот, более узкий, маршрут
  // перебивает общий «**/*» для одного конкретного файла.
  if (ПУТЬ_КОПИИ) {
    if (!fs.existsSync(ПУТЬ_КОПИИ)) {
      console.error('Копия не найдена: ' + ПУТЬ_КОПИИ);
      process.exit(2);
    }
    const текстКопии = fs.readFileSync(ПУТЬ_КОПИИ, 'utf8');
    // Глоб-строка с кириллицей НЕ матчит запрос: браузер шлёт адрес файла
    // закодированным («%D1%80%D0%B5%D0%B9…»), playwright сверяет шаблон
    // именно с этим видом — та же ловушка, что описана в «перехватить»
    // (tests/браузер-робот.js). Поэтому маршрут — функция-предикат: сама
    // раскодирует адрес и сверяет по имени файла без хвоста «?v=33».
    await страница.route(function (url) {
      let адрес = url.href;
      try { адрес = decodeURIComponent(адрес); } catch (о) { /* оставим как есть */ }
      return /\/js\/рейтинг-экран\.js(?:\?|$)/.test(адрес);
    }, function (путь) {
      путь.fulfill({ status: 200, contentType: 'text/javascript; charset=utf-8', body: текстКопии });
    });
  }

  await страница.goto(АДРЕС_СТРАНИЦЫ + '?сервер=' + encodeURIComponent(АДРЕС_СЕРВЕРА_ВЫДУМАННЫЙ),
    { waitUntil: 'domcontentloaded' });
  await страница.waitForFunction(() => Boolean(window.ЭкранРейтинга), { timeout: 8000 });

  await страница.evaluate(() => window.ЭкранРейтинга.открыть('дурак'));
  await страница.waitForFunction(() => {
    const э = document.getElementById('экран-рейтинга-игроков');
    return Boolean(э && э.classList.contains('экран--виден'));
  }, { timeout: 8000 });

  console.log('\n=== Контроль: «Дурак» (картинка есть, запаски быть не должно) ===');
  await дождатьсяРешенияПоЗначку(страница);
  const дурак = await значокНаКнопке(страница);
  проверить('«Дурак»: кнопка выбора игры нашлась', дурак.естьКнопка);
  проверить('«Дурак»: запасного кружка НЕТ (картинка своя есть)', дурак.естьЗапаска === false,
    JSON.stringify(дурак));
  проверить('«Дурак»: <img> загрузился (naturalWidth > 0)', дурак.естьImg && дурак.naturalWidth > 0,
    JSON.stringify(дурак));

  const ИГРЫ_БЕЗ_ЗНАЧКА = [
    { ключ: 'домино', подпись: 'Домино', буква: 'Д' },
    { ключ: 'морской-бой', подпись: 'Морской бой', буква: 'М' }
  ];

  for (const игра of ИГРЫ_БЕЗ_ЗНАЧКА) {
    console.log('\n=== «' + игра.подпись + '» (картинки нет — img/рейтинг/' + игра.ключ + '.png отсутствует) ===');
    await выбратьИгруВПанели(страница, игра.ключ);
    await дождатьсяРешенияПоЗначку(страница);

    const состояние = await значокНаКнопке(страница);
    проверить('«' + игра.подпись + '»: кнопка выбора игры нашлась', состояние.естьКнопка);
    проверить('«' + игра.подпись + '»: запасной кружок найден вместо битой картинки',
      состояние.естьЗапаска === true, JSON.stringify(состояние));
    проверить('«' + игра.подпись + '»: буква в запасном кружке — «' + игра.буква + '»',
      состояние.текстЗапаски === игра.буква, 'получено: ' + JSON.stringify(состояние.текстЗапаски));

    const битые = await битыеКартинки(страница);
    проверить('«' + игра.подпись + '»: на экране нет ни одной битой <img> (naturalWidth=0)',
      битые.length === 0, битые.length ? 'битые: ' + битые.join(', ') : 'битых нет');
  }

  проверить('консоль браузера чистая (кроме ожидаемого 404 на img/рейтинг/ и внешнего telegram-web-app.js)',
    красные.length === 0, красные.join(' | '));

  await контекст.close();
  await браузер.close();
}

(async () => {
  if (ПУТЬ_КОПИИ) {
    console.log('*** ЛОМАЮЩИЙ ЗАПУСК --копия=' + ПУТЬ_КОПИИ + ': js/рейтинг-экран.js подменён испорченной ' +
      'копией без обработки ошибки у <img> — проверки «запасной кружок найден» и «нет битой <img>» обязаны покраснеть ***\n');
  }
  console.log('=== Запасной значок игры в рейтинге: ' + АДРЕС_СТРАНИЦЫ + ' ===');
  await запуститьПрогон();
  console.log('\nИтого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
})().catch((ошибка) => {
  console.error('Проверка упала: ' + (ошибка && ошибка.stack || ошибка));
  process.exit(2);
});
