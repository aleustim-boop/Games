'use strict';

/* Проверка кнопки «Друзья» на экране «Профиль» (общее/js/профиль-экран.js, Ф3
   плана штаб/план-друзья-везде.md). Браузера нет: поднимаем файл в
   поддельном браузере (tests/поддельный-браузер.js).

   Случаи:
     1. window.ЭкранДрузей подключён с самого начала — кнопка
        #кнопка-профиля-друзья на месте (класс «кнопка кнопка--мелкая»,
        текст «Друзья»), клик зовёт ЭкранДрузей.открыть() ровно один раз.
     2. Двери нет вовсе — узла кнопки нет (мёртвых кнопок не бывает).
     3. Двери не было при первом открытии, появилась позже (модуль
        общее/js/друзья-экран.js подключился после профиля) — при втором
        открытии кнопка появляется; повторные открытия её не множат.

   Ломающий запуск: node tests/профиль-кнопка-друзья.js --сломать —
   портит КОПИЮ файла во временной папке (os.tmpdir(), путь печатается),
   файл проекта не трогает ни на минуту. Порча: кнопка никогда не
   строится — случай 1 обязан покраснеть.
   node tests/профиль-кнопка-друзья.js --сломать-всегда — вторая копия,
   где кнопка ставится независимо от наличия двери — случай 2 (без
   двери) обязан покраснеть.
   Свой исходник можно подсунуть доводом --файл=<путь>. */

const fs = require('fs');
const os = require('os');
const path = require('path');
const бр = require(path.join(__dirname, 'поддельный-браузер.js'));

const КОРЕНЬ = path.join(__dirname, '..');
const ФАЙЛ_ПРОЕКТА = path.join(КОРЕНЬ, 'общее', 'js', 'профиль-экран.js');

const доводФайла = process.argv.find(function (д) { return д.indexOf('--файл=') === 0; });
const СЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;
const СЛОМАТЬ_ВСЕГДА = process.argv.indexOf('--сломать-всегда') !== -1;

let файлПрофиля = доводФайла ? доводФайла.split('=')[1] : ФАЙЛ_ПРОЕКТА;
let исходник = fs.readFileSync(файлПрофиля, 'utf8');

/* --------------------------------------------------------------------
   Ломающий запуск 1: копия, где кнопка «Друзья» никогда не строится.
   -------------------------------------------------------------------- */
if (СЛОМАТЬ) {
  const ИСКОМОЕ = "const кнопка = кнопкаЭл(КНОПКА_ДРУЗЬЯ, 'Друзья', 'кнопка кнопка--мелкая', открытьДрузей);";
  if (исходник.indexOf(ИСКОМОЕ) === -1) {
    console.log('ОШИБКА: приём порчи --сломать устарел — в ' + файлПрофиля + ' не нашлась строка:');
    console.log('  ' + ИСКОМОЕ);
    process.exit(1);
  }
  const испорченный = исходник.split(ИСКОМОЕ).join('return; /* порча --сломать: кнопка «Друзья» никогда не строится */');
  файлПрофиля = path.join(os.tmpdir(), 'профиль-экран-без-кнопки-друзья-' + process.pid + '.js');
  fs.writeFileSync(файлПрофиля, испорченный, 'utf8');
  исходник = испорченный;
  console.log('Ломающий запуск --сломать: порчу КОПИЮ, файл проекта не тронут.');
  console.log('  копия: ' + файлПрофиля);
  console.log('  порча: кнопка «Друзья» никогда не появляется на экране.');
  console.log('');
}

/* --------------------------------------------------------------------
   Ломающий запуск 2: копия, где кнопка ставится ВСЕГДА, даже без двери.
   -------------------------------------------------------------------- */
if (СЛОМАТЬ_ВСЕГДА) {
  const ИСКОМОЕ = "if (!дверьДрузей()) {";
  if (исходник.indexOf(ИСКОМОЕ) === -1) {
    console.log('ОШИБКА: приём порчи --сломать-всегда устарел — в ' + файлПрофиля + ' не нашлась строка:');
    console.log('  ' + ИСКОМОЕ);
    process.exit(1);
  }
  const испорченный = исходник.split(ИСКОМОЕ).join('if (false) { /* порча --сломать-всегда: кнопка ставится и без двери */');
  файлПрофиля = path.join(os.tmpdir(), 'профиль-экран-кнопка-друзья-всегда-' + process.pid + '.js');
  fs.writeFileSync(файлПрофиля, испорченный, 'utf8');
  исходник = испорченный;
  console.log('Ломающий запуск --сломать-всегда: порчу КОПИЮ, файл проекта не тронут.');
  console.log('  копия: ' + файлПрофиля);
  console.log('  порча: кнопка «Друзья» ставится независимо от наличия window.ЭкранДрузей.');
  console.log('');
}

let всегоПроверок = 0;
let провалов = 0;

function проверить(имя, годно) {
  всегоПроверок += 1;
  console.log((годно ? '  ok  ' : ' ПЛОХО ') + имя);
  if (!годно) провалов += 1;
}

function ждать(мс) { return new Promise(function (r) { setTimeout(r, мс || 40); }); }

/** Поднять экран профиля в поддельном браузере без соседних дверей рейтинга. */
function поднятьПрофиль() {
  return бр.поднять(исходник, { имяФайла: 'общее/js/профиль-экран.js' });
}

const ИД_КНОПКИ = 'кнопка-профиля-друзья';

async function прогон() {

  /* ============ Случай 1: window.ЭкранДрузей подключён сразу ============ */
  const п1 = поднятьПрофиль();
  проверить('дверь window.ЭкранПрофиля.открыть есть',
    Boolean(п1.окно.ЭкранПрофиля) && typeof п1.окно.ЭкранПрофиля.открыть === 'function');
  let вызовыОткрыть1 = 0;
  п1.окно.ЭкранДрузей = { открыть: function () { вызовыОткрыть1 += 1; } };
  п1.окно.ЭкранПрофиля.открыть('дурак');
  await ждать();

  const кнопка1 = п1.документ.getElementById(ИД_КНОПКИ);
  проверить('с window.ЭкранДрузей: кнопка #кнопка-профиля-друзья построена', Boolean(кнопка1));
  проверить('кнопка «Друзья» — класс «кнопка кнопка--мелкая», как «Как я играю»',
    Boolean(кнопка1) && кнопка1.classList.contains('кнопка') && кнопка1.classList.contains('кнопка--мелкая'));
  проверить('текст кнопки — «Друзья»', Boolean(кнопка1) && кнопка1.textContent === 'Друзья');
  if (кнопка1) кнопка1.click();
  проверить('клик по кнопке зовёт window.ЭкранДрузей.открыть() ровно один раз (позвано ' + вызовыОткрыть1 + ' раз)',
    вызовыОткрыть1 === 1);
  проверить('ошибок в консоли нет (дверь подключена)', п1.ошибкиКонсоли.length === 0);

  /* ================= Случай 2: двери window.ЭкранДрузей нет вовсе ================= */
  const п2 = поднятьПрофиль();
  п2.окно.ЭкранПрофиля.открыть('дурак');
  await ждать();
  проверить('без window.ЭкранДрузей: узла кнопки #кнопка-профиля-друзья нет вовсе',
    п2.документ.getElementById(ИД_КНОПКИ) === null);
  проверить('без window.ЭкранДрузей: экран профиля всё равно построен',
    Boolean(п2.документ.getElementById('экран-профиля-игрока')));
  проверить('ошибок в консоли нет (без двери)', п2.ошибкиКонсоли.length === 0);

  /* ========== Случай 3: дверь появилась ПОЗЖЕ первого открытия ========== */
  const п3 = поднятьПрофиль();
  п3.окно.ЭкранПрофиля.открыть('дурак');
  await ждать();
  проверить('до появления двери: кнопки ещё нет',
    п3.документ.getElementById(ИД_КНОПКИ) === null);

  п3.окно.ЭкранДрузей = { открыть: function () {} };
  п3.окно.ЭкранПрофиля.открыть('дурак');
  await ждать();
  проверить('дверь появилась позже (общее/js/друзья-экран.js догрузился) — при повторном открытии кнопка на месте',
    Boolean(п3.документ.getElementById(ИД_КНОПКИ)));

  // Третье открытие с уже подключённой дверью — кнопка не должна размножиться.
  п3.окно.ЭкранПрофиля.открыть('дурак');
  await ждать();
  проверить('повторные открытия не плодят вторую кнопку (ровно один узел)',
    п3.документ.querySelectorAll('#' + ИД_КНОПКИ).length === 1);
  проверить('ошибок в консоли нет (дверь появилась позже)', п3.ошибкиКонсоли.length === 0);

  console.log('');
  console.log('Итого проверок: ' + всегоПроверок + ', провалов: ' + провалов);

  if (СЛОМАТЬ || СЛОМАТЬ_ВСЕГДА) {
    if (провалов === 0) {
      console.log('ПЛОХО: ломающий запуск не покраснел — проверка ничего не стережёт.');
      process.exit(1);
    }
    console.log('Ломающий запуск покраснел, как и должен (испорченная копия: ' + файлПрофиля + ').');
    process.exit(0);
  }

  process.exit(провалов ? 1 : 0);
}

прогон().catch(function (ошибка) {
  console.error('Ошибка прогона:', ошибка);
  process.exit(1);
});
