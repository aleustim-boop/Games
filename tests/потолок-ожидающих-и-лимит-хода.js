/* ---------------- Подпись Telegram — по правилу сервера ---------------- */

function подписать(поля) {
  const строки = Object.keys(поля).map(function (к) { return к + '=' + поля[к]; }).sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(ТОКЕН).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}

function подпись(номер, имя) {
  const поля = {
    query_id: 'AAZ' + номер,
    user: JSON.stringify({ id: номер, first_name: имя }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  поля.hash = подписать(поля);
  return Object.keys(поля)
    .map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(поля[к]); })
    .join('&');
}

/* ---------------- Разговор с дверями ---------------- */

function спросить(путь, тело) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: АДРЕС, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (сбой) { разобрано = null; }
        готово({ код: ответ.statusCode, тело: разобрано || {}, текст: текст });
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

function задержка(мс) {
  return new Promise(function (готово) { setTimeout(готово, мс); });
}

async function создатьСтол(кто, имя, игра) {
  const ответ = await спросить('/создать', { initData: подпись(кто, имя), имя: имя, игра: игра });
  if (ответ.код !== 200 || !ответ.тело.код) throw new Error('стол для ' + имя + ' не создан: ' + ответ.текст);
  return { код: ответ.тело.код, пропуск: ответ.тело.пропуск, кто: кто, имя: имя };
}

async function войтиВторым(стол, кто, имя) {
  const ответ = await спросить('/войти', { код: стол.код, имя: имя, initData: подпись(кто, имя) });
  if (ответ.код !== 200 || !ответ.тело.пропуск) throw new Error('вход ' + имя + ' не удался: ' + ответ.текст);
  return { код: стол.код, пропуск: ответ.тело.пропуск, кто: кто, имя: имя };
}

async function видИгрока(место) {
  const ответ = await спросить('/состояние', { код: место.код, пропуск: место.пропуск });
  return ответ.тело.состояние || {};
}

/* ---------------- А) Потолок висящих опросов ---------------- */

async function потолокОжидающих() {
  console.log('А) Потолок висящих опросов «что нового» на одно место (не больше 4)');

  const хозяйка = await создатьСтол(951, 'Аня', 'дурак');
  const второй = await войтиВторым(хозяйка, 952, 'Боря');
  проверить(Boolean(второй.пропуск), 'А: второй игрок (Боря) сел за тот же стол');

  const версия = (await видИгрока(хозяйка)).версия;
  проверить(Number.isFinite(версия), 'А: у комнаты есть номер версии для опроса');

  const результаты = new Array(6).fill(null);
  const времена = new Array(6).fill(null);
  const промисыАни = [];
  for (let i = 0; i < 6; i++) {
    const метка = i;
    const начало = Date.now();
    const p = спросить('/что-нового', { код: хозяйка.код, пропуск: хозяйка.пропуск, версия: версия })
      .then(function (р) { результаты[метка] = р; времена[метка] = Date.now() - начало; })
      .catch(function (е) { результаты[метка] = { код: 0, тело: {}, текст: 'сбой сети: ' + е.message }; времена[метка] = Date.now() - начало; });
    промисыАни.push(p);
    // Небольшая пауза между СТАРТАМИ отправки (не между ответами!) — чтобы
    // сервер гарантированно получил все шесть в том порядке, в каком мы их
    // выпустили, и «самый свежий из висящих» на каждом шаге был предсказуем.
    await задержка(20);
  }

  let результатБори = null;
  const началоБори = Date.now();
  let времяБори = null;
  спросить('/что-нового', { код: второй.код, пропуск: второй.пропуск, версия: версия })
    .then(function (р) { результатБори = р; времяБори = Date.now() - началоБори; })
    .catch(function (е) { результатБори = { код: 0, тело: {}, текст: 'сбой сети: ' + е.message }; времяБори = Date.now() - началоБори; });

  /* Контрольная точка на ~2 с от начала: выселение из СПИСКА ждущих
     происходит сразу (место под потолком освобождается немедленно), но
     САМ ОТВЕТ выселенному уходит только через ПАУЗА_ВЫСЕЛЕННОГО_МС = 3000
     после этого. Поэтому через 2 с не должен быть отвечен ВООБЩЕ никто —
     ни выселенные (их пауза ещё не истекла), ни тем более первый/последний. */
  await задержка(2000);
  проверить(результаты.every(function (р) { return р === null; }),
    'А: через ~2с ещё НИКТО из шести не отвечен (выселенным ещё идёт пауза перед ответом, не мгновенно)');
  проверить(результатБори === null, 'А: через ~2с второй игрок (Боря) тоже ещё не отвечен — его опрос обычный, никем не задет');

  // Досыпаем до ~6,5 с от начала — окно, в котором обязаны ответить
  // выселенные (2–6 с после выселения), с запасом на локальные накладные.
  await задержка(4500);

  const разрешились = результаты.map(function (р, i) { return р !== null ? i : -1; }).filter(function (i) { return i >= 0; });
  проверить(разрешились.length === 2, 'А: к ~6,5с ровно 2 из 6 запросов Ани получили ответ (остальные 4 всё ещё висят), получили: [' + разрешились.join(',') + ']');

  проверить(результаты[0] === null, 'А: самый ПЕРВЫЙ запрос (№1) не выселен вовсе — всё ещё висит и после 6,5с');
  проверить(результаты[5] === null, 'А: самый ПОСЛЕДНИЙ отправленный запрос (№6) не выселен — новый запрос никогда не выселяет сам себя');
  проверить(результаты[3] !== null, 'А: запрос №4 (был самым свежим на приходе №5) выселен');
  проверить(результаты[4] !== null, 'А: запрос №5 (был самым свежим на приходе №6) выселен');

  for (const i of [3, 4]) {
    if (результаты[i]) {
      проверить(результаты[i].код === 200 && результаты[i].тело.изменилось === false,
        'А: выселенный запрос №' + (i + 1) + ' получил обычный ответ {изменилось:false} (' + результаты[i].текст.slice(0, 100) + ')');
      проверить(времена[i] >= 2000 && времена[i] < 6000,
        'А: выселенный запрос №' + (i + 1) + ' ответил в окне 2–6с (не мгновенно и не по таймеру 25с), а именно через ' + времена[i] + ' мс');
    }
  }

  проверить(результатБори === null, 'А: второй игрок (Боря) своими запросами не задет — его опрос всё ещё висит и после 6,5с');

  // Итоговая версия комнаты после всего этого не выросла: ни один из
  // выселенных ответов не был настоящей новостью, только «времени вышло».
  проверить((await видИгрока(хозяйка)).версия === версия, 'А: версия комнаты не изменилась — выселение не считается событием стола');
}

/* ---------------- Б) Лимит секунд на ход ---------------- */

function настроить(стол, значение) {
  return спросить('/ход', { код: стол.код, пропуск: стол.пропуск, действие: 'настройки', лимитСекундНаХод: значение });
}

function лимитВКомнате(стол) {
  const найдено = комнаты.найтиИгрока(стол.код, стол.пропуск);
  if (!найдено) throw new Error('комнату/игрока не нашли напрямую через комнаты.найтиИгрока — стол ' + стол.код);
  return найдено.комната.лимитСекундНаХод;
}

async function лимитХода() {
  console.log('Б) Приём настройки лимитСекундНаХод от хозяина');

  const стол = await создатьСтол(961, 'Егор', 'дурак');
  проверить(лимитВКомнате(стол) === 0, 'Б: по умолчанию лимит 0 (без таймера)');

  await настроить(стол, '15');
  проверить(лимитВКомнате(стол) === 15, 'Б: строка "15" сохранена как число 15');

  await настроить(стол, 7.9);
  проверить(лимитВКомнате(стол) === 7, 'Б: 7.9 округлено вниз до 7 (Math.floor)');

  await настроить(стол, -3);
  проверить(лимитВКомнате(стол) === 0, 'Б: отрицательное -3 сохранено как 0 (не отрицательное и не прежнее значение)');

  await настроить(стол, 'abc');
  проверить(лимитВКомнате(стол) === 0, 'Б: не-число "abc" — как будто поле не прислано, прежнее (0) не изменилось');

  await настроить(стол, { x: 1 });
  проверить(лимитВКомнате(стол) === 0, 'Б: объект {x:1} — как будто поле не прислано, прежнее (0) не изменилось');

  await настроить(стол, 'Infinity');
  проверить(лимитВКомнате(стол) === 0, 'Б: строка "Infinity" — как будто поле не прислано, прежнее (0) не изменилось');

  // Усиленная проверка: то же самое, но от НЕНУЛЕВОГО прежнего значения —
  // отличает «прежнее не трогаем» от возможной ошибки «мусор всегда пишем
  // как 0», которую предыдущие шаги поймать не могли (там и так было 0).
  await настроить(стол, '9');
  проверить(лимитВКомнате(стол) === 9, 'Б: строка "9" сохранена как число 9 (готовим ненулевое прежнее значение)');

  await настроить(стол, 'abc');
  проверить(лимитВКомнате(стол) === 9, 'Б: не-число "abc" от ненулевого прежнего (9) — прежнее НЕ сброшено в 0');
}

