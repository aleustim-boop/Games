/* ---------- Наблюдение за знаками ---------- */
const наблюдаемые = [];   // { комната, последний, отЛичин: [ { номер, когда, этап } ], событие, ходовЛичин }
function осмотреть() {
  for (const н of наблюдаемые) {
    // Ходы личины: событие комнаты сменилось, и сделала его личина.
    if (н.комната.номерСобытия !== н.событие) {
      н.событие = н.комната.номерСобытия;
      const событие = н.комната.событие;
      const кто = событие ? н.комната.игроки[событие.кто] : null;
      if (кто && кто.этоБот && кто.личина) н.ходовЛичин++;
    }
    const знак = н.комната.знакВнимания;
    if (!знак || знак.порядковый === н.последний) continue;
    н.последний = знак.порядковый;
    const игрок = н.комната.игроки[знак.кто];
    if (игрок && игрок.этоБот && игрок.личина) {
      н.отЛичин.push({ номер: знак.номер, когда: знак.когда, этап: н.комната.этап });
    }
  }
}

/** Местo личины за столом (первое). */
function местоЛичины(комната) {
  return Object.keys(комната.игроки).find(function (место) {
    const игрок = комната.игроки[место];
    return игрок && игрок.этоБот && игрок.личина && !игрок.ушёл;
  }) || null;
}

let телеграм = 8100;
/** Стол личин на двоих + человек; ждём начала партии. */
function столСЧеловеком(игра) {
  const стол = комнаты.создатьСтолЛичин(игра, { мест: 2, сколькоЛичин: 1 });
  if (!стол.ок) return { ошибка: 'стол не открылся: ' + JSON.stringify(стол) };
  const вход = комнаты.войтиВКомнату(стол.код, { имя: 'Гость', телеграм: ++телеграм });
  if (!вход.ок) return { ошибка: 'человек не сел: ' + JSON.stringify(вход) };
  const я = комнаты.найтиИгрока(вход.код, вход.пропуск);
  if (!я) return { ошибка: 'человек не найден по пропуску' };
  const н = { комната: я.комната, последний: я.комната.знакВнимания ? я.комната.знакВнимания.порядковый : null, отЛичин: [],
              событие: я.комната.номерСобытия, ходовЛичин: 0 };
  наблюдаемые.push(н);
  const итог = { код: вход.код, пропуск: вход.пропуск, комната: я.комната, ктоЯ: я.ктоЯ, наблюдение: н,
                 личина: местоЛичины(я.комната) };
  итог.опрос = function () { комнаты.найтиИгрока(итог.код, итог.пропуск); };
  итог.знакиДоПартии = 0;
  for (let шаг = 0; шаг < 60 && итог.комната.этап !== 'игра'; шаг++) {
    прошло(1000);
    итог.опрос();
    комнаты.прибратьсяСейчас();
    осмотреть();
  }
  итог.знакиДоПартии = н.отЛичин.filter(function (з) { return з.этап === 'ожидание'; }).length;
  return итог;
}

/** Человек шлёт знак; ответ комнаты. */
function послать(стол, номер) {
  const ответ = комнаты.сделатьХод(стол.комната, стол.ктоЯ, { действие: 'эмоция', номер: номер });
  осмотреть();
  return ответ;
}

/** Человек делает первый законный ход в шашках; ответ комнаты. */
function сходитьЧеловеком(стол) {
  const ходы = ПРАВИЛА_ШАШЕК.возможныеХоды(стол.комната.партия.доска);
  if (!ходы.length) return { принято: false, причина: 'законных ходов нет' };
  const ход = ходы[0];
  const ответ = комнаты.сделатьХод(стол.комната, стол.ктоЯ, {
    действие: 'ход', откуда: ход.откуда, куда: ход.куда, побитые: ход.побитые, станетДамкой: ход.станетДамкой
  });
  осмотреть();
  return ответ;
}

/** Ждать (по секунде, с уборкой), пока очередь не придёт к человеку. */
function дождатьсяХодаЧеловека(стол, игра) {
  for (let шаг = 0; шаг < 30 && игра.чейХод(стол.комната.партия) !== стол.ктоЯ; шаг++) {
    прошло(1000); стол.опрос();
  }
  return игра.чейХод(стол.комната.партия) === стол.ктоЯ;
}

