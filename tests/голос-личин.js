  проверить(сдался && сдался.принято === true, 'человек сдался' + (сдался && сдался.причина ? ' (' + сдался.причина + ')' : ''));
  проверить(третий.комната.этап !== 'игра', 'партия кончилась (этап ' + третий.комната.этап + ')');
