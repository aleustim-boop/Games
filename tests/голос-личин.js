const очередь = new Map();   // таймер → { когда, дело, доводы, порядок }
let номерТаймера = 0;
function ПоддельныйТаймер(номер) { this.номер = номер; }
ПоддельныйТаймер.prototype.unref = function () { return this; };
ПоддельныйТаймер.prototype.ref = function () { return this; };
