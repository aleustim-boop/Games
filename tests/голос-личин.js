/** Сдвинуть часы на мс, по дороге выполняя созревшие таймеры по порядку. */
function прошло(мс) {
  const до = сейчас + мс;
  for (;;) {
    let ближний = null;
    let запись = null;
    for (const [таймер, з] of очередь) {
      if (з.когда > до) continue;
      if (!запись || з.когда < запись.когда || (з.когда === запись.когда && з.порядок < запись.порядок)) {
        ближний = таймер; запись = з;
      }
    }
    if (!ближний) break;
    очередь.delete(ближний);
    if (запись.когда > сейчас) сейчас = запись.когда;
    запись.дело.apply(null, запись.доводы);
    осмотреть();
  }
  сейчас = до;
}

