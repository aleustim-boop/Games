  // «Сдаться» после конца партии серверу не уходит.
  м.нажать('захват-сдаться-да');
  await отпуститьВсё();
  проверка('конец: «Сдаться» после конца партии не шлёт запрос', м.сеть.ходы.length === 0, JSON.stringify(м.сеть.ходы));

