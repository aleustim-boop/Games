  const { партия: конечная, первый } = партияКонца();
  const к = мир();
  к.мост.показатьВид(первый);
  const следК = следитьЗаПодписями(к);
  const конец = видКонца(конечная, 'а', 2);
  к.мост.показатьВид(конец);
  const ждёмК = ожидаемоеРаскрытие(к, конец.захват, конец.захват.хозяеваДо);
  к.часы.прошло(всегоМсРаскрытия(к) + 10);
