/** Часы сервера сдвинуты на сдвигМс на время дела: так вид «через 9 секунд после разбора» — настоящий. */
function сЧасамиСервера(сдвигМс, дело) {
  const настоящие = СерверЗахвата.сейчас;
  СерверЗахвата.сейчас = () => настоящие() + сдвигМс;
  try { return дело(); } finally { СерверЗахвата.сейчас = настоящие; }
}

