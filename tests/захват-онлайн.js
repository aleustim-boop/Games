function оживитьОкна(документ) {
  документ.querySelectorAll('dialog').forEach(окно => {
    окно.open = false;
    окно.showModal = () => { окно.open = true; };
    окно.close = () => { окно.open = false; };
  });
}

/** опции.память — память браузера от прошлого мира: так проверка «перезагружает» страницу. */
function мир(опции) {
  const документ = сделатьДокумент();
  собратьРазметку(исходникСтраницы, документ);
  оживитьОкна(документ);
  const память = (опции && опции.память) || сделатьПамять(false);
  const р = поднять('', { память: память, документ: документ });
  const часы = поставитьЧасы(р.песочница);
  // Панель «Сказать» берёт ширину окна общим именем innerWidth, как в браузере.
  if (р.песочница.innerWidth === undefined) р.песочница.innerWidth = р.окно.innerWidth || 390;
  // Бросок летит через стол анимацией: подделке хватает «меньше движения» и пустой анимации (до цели не долетает).
  if (!р.песочница.matchMedia) р.песочница.matchMedia = () => ({ matches: true });
  const создатьУзел = документ.createElement.bind(документ);
  документ.createElement = тег => { const у = создатьУзел(тег); if (!у.animate) у.animate = () => ({}); return у; };
  // Рисунки карты (Г1б): по опции «рисунки» ставим поддельную Image; опции.битые — пути, что «не нашлись»;
  // опции.кадры: 'ручные' (requestAnimationFrame копит дела) или 'нет' (его в окне нет совсем).
  const рис = { картинки: null, загрузки: [], раскладки: [], рисование: [], кадры: { очередь: [] } };
  рис.кадры.выпустить = () => { рис.кадры.очередь.splice(0).forEach(дело => дело()); };
  if (опции && опции.рисунки) рис.картинки = поставитьКартинки(р.окно, опции.битые);
  const сеть = сделатьСеть();
  р.окно.Сеть = сеть;
  const стрелки = [];
  р.окно.Телеграм = {
    показатьСтрелку: дело => { стрелки.push(дело); return true; }, кнопкаНастроек: () => true, отклик: () => {},
    имяИгрока: () => 'Аня', вибрацияДоступна: () => false, вибрацияВключена: () => false, включитьВибрацию: () => {}
  };
  for (const часть of ЧАСТИ_ДО_ЭКРАНА) {
    vm.runInContext(fs.readFileSync(path.join(КОРЕНЬ, 'js', часть), 'utf8'), р.песочница, { filename: 'js/' + часть });
  }
  if (опции && опции.рисунки) {
    const КВ = р.окно.ЗахватКартаВид;
    const загрузитьНастоящую = КВ.загрузитьРисунки;
    КВ.загрузитьРисунки = function (список) { рис.загрузки.push(список.map(в => в.путь)); return загрузитьНастоящую.apply(this, arguments); };
    const собратьНастоящую = КВ.собратьРаскладку;
    КВ.собратьРаскладку = function (партия, параметры) { рис.раскладки.push({ игроки: партия.игроки.slice(), хозяева: партия.хозяева.slice(), параметры: параметры || {} }); return собратьНастоящую.apply(this, arguments); };
    const кисть = {};
    ['save', 'restore', 'setTransform', 'clearRect', 'drawImage', 'fillRect', 'fill', 'stroke', 'arc', 'beginPath', 'createLinearGradient', 'createRadialGradient',
      'translate', 'rotate', 'scale', 'moveTo', 'lineTo', 'closePath', 'clip', 'rect', 'quadraticCurveTo', 'bezierCurveTo', 'strokeRect', 'setLineDash', 'addColorStop']
      .forEach(имя => { кисть[имя] = (...доводы) => { рис.рисование.push({ имя, доводы, альфа: кисть.globalAlpha === undefined ? 1 : кисть.globalAlpha }); }; });
    документ.getElementById('захват-холст').getContext = () => кисть;
    if (опции.кадры === 'ручные') р.окно.requestAnimationFrame = дело => { рис.кадры.очередь.push(дело); return рис.кадры.очередь.length; };
    if (опции.кадры === 'нет') р.окно.requestAnimationFrame = undefined;
  }
  vm.runInContext(исходникЭкрана, р.песочница, { filename: ФАЙЛ_ЭКРАНА });
  // опции.доМодуля(окно) — подменить что-то в окне до загрузки модуля (например, старую память из кэша).
  if (опции && опции.доМодуля) опции.доМодуля(р.окно);
  vm.runInContext(исходникМодуля, р.песочница, { filename: ФАЙЛ_МОДУЛЯ });
  // Окно панели «Сказать» модуль создаёт сам (его нет в разметке) — оживляем и его.
  оживитьОкна(документ);
  const м = {
    окно: р.окно, документ: документ, часы: часы, сеть: сеть, память: память, стрелки: стрелки, рисунки: рис, ошибки: р.ошибкиКонсоли,
    Правила: р.спросить('window.ЗахватПравила'),
    КартаВид: р.спросить('window.ЗахватКартаВид'),
    узел: id => документ.getElementById(id),
    видна: у => !!у && !у.classList.contains('скрыт')
  };
  м.нажать = id => { const у = м.узел(id); if (!у) throw new Error('Нет узла ' + id); у.click(); };
  м.видимыйЭкран = id => !!м.узел(id) && м.узел(id).classList.contains('экран--виден');
  м.сохранение = () => память.getItem(КЛЮЧ_СОХРАНЕНИЯ);
  м.пилюля = () => (м.видна(м.узел('захват-совет')) ? м.узел('захват-совет-текст').textContent : '');
  // Общее окно «Выйти из партии?» листа «⋯» (js/лист-ещё.js строит его сам): часть по классу.
  м.частьПлашки = имя => { const п = м.узел('плашка-завершить'); return п ? п.querySelector('.плашка-завершить__' + имя) : null; };
  м.нажатьВПлашке = имя => { const к = м.частьПлашки(имя); if (!к) throw new Error('Нет кнопки окна ухода: ' + имя); к.click(); };
  м.стрелка = () => { const с = стрелки[стрелки.length - 1]; if (typeof с !== 'function') throw new Error('Стрелка Telegram не привязана'); с(); };
  м.мост = р.окно.ИграПоСети;
  м.модуль = р.окно.ЗахватОнлайн;
  м.экран = р.окно.ЗахватЭкран;
  м.лобби = р.окно.ОнлайнЛобби;
  if (!м.мост || !м.модуль) throw new Error('Модуль не поставил window.ИграПоСети или window.ЗахватОнлайн');
  if (!м.экран) throw new Error('Экран не поставил window.ЗахватЭкран');
  return м;
}

