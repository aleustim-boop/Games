const внутри = (папка, путь) => !path.relative(папка, путь).startsWith('..') && !path.isAbsolute(path.relative(папка, путь));

function сломатьИПроверить() {
  const своя = значениеДовода('--сломать');
  const папка = своя ? path.resolve(своя) : fs.mkdtempSync(path.join(os.tmpdir(), 'захват-онлайн-лом-'));
  if (внутри(КОРЕНЬ, папка)) {
    console.log('Папка порчи внутри проекта — копии кладутся только вне его: ' + папка);
    process.exit(3);
  }
  fs.mkdirSync(папка, { recursive: true });
  let покраснело = 0, худшийКод = 0;
  ПОРЧИ.forEach((порча, номер) => {
    const экран = порча.файл === 'экран';
    const исходник = экран ? исходникЭкрана : исходникМодуля;
    // «также» — добавочные замены той же порчи: когда одну защиту прикрывает вторая, портить надо обе разом.
    const замены = [{ было: порча.было, стало: порча.стало }].concat(порча.также || []);
    const неТак = замены.map(з => исходник.split(з.было).length - 1).find(мест => мест !== 1);
    if (неТак !== undefined) {
      console.log('Порча ' + (номер + 1) + ' («' + порча.имя + '»): место порчи найдено ' + неТак + ' раз вместо одного — код 3');
      худшийКод = Math.max(худшийКод, 3);
      return;
    }
    const копия = path.join(папка, 'порча-' + (номер + 1) + (экран ? '-экран' : '-модуль') + '.js');
    fs.writeFileSync(копия, замены.reduce((текст, з) => текст.replace(з.было, () => з.стало), исходник), 'utf8');
    const запуск = spawnSync(process.execPath, [__filename, экран ? '--файл-экрана' : '--файл', копия], { encoding: 'utf8' });
    const красных = (запуск.stdout.match(/^ПРОВАЛ: .*/gm) || []);
    const покраснела = запуск.status === 1 && красных.length > 0;
    if (покраснела) покраснело++;
    else худшийКод = Math.max(худшийКод, 2);
    console.log('Порча ' + (номер + 1) + ' («' + порча.имя + '»): код выхода ' + запуск.status + ', красных пунктов ' + красных.length);
    красных.forEach(с => console.log('   ' + с));
  });
  console.log('Папка копий: ' + папка);
  console.log('Поломок: ' + ПОРЧИ.length + ', покраснело: ' + покраснело);
  process.exit(худшийКод);
}

