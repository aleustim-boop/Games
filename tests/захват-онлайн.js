  // Сеть идёт, а человек ушёл к партии с ботами мимо нас: чужой отсчёт и тик над ботами не нужны.
  const м4 = мир();
  let тиков4 = 0;
  м4.окно.ЗахватЗвук.тик = () => { тиков4++; };
