  м2.модуль.стол().поставитьВойска(мояОбласть(вид2), 1);
  м2.часы.прошло(100);
  const конец2 = JSON.parse(JSON.stringify(видДля(партия, 'а', 2)));
  конец2.завершена = true;
  м2.мост.показатьВид(конец2);
  м2.часы.прошло(1000);
  await отпуститьВсё();
  проверка('конец: правка, ждавшая 400 мс, на конец партии не уходит', м2.сеть.черновики.length === 0, JSON.stringify(м2.сеть.черновики));

  // Новая партия (сыграноПартий выросло, завершена нет) — снова можно.
  const новая = видДля(новаяПартия(15), 'а', 4, 1);
