/**
 * Узлам имён #захват-имя-1..6 — разные места на экране: строка n стоит на x = 10 + 10n, низ — 100n + 12.
 * Облако панель ставит по узлу сказавшего: left = x, top = низ − 12 (js/деберц-сказать.js).
 */
function разнестиИмена(м) {
  const где = {};
  for (let n = 1; n <= 6; n++) {
    const у = м.узел('захват-имя-' + n);
    if (!у) throw new Error('Нет узла #захват-имя-' + n);
    const x = 10 + 10 * n, низ = 100 * n + 12;
    у.getBoundingClientRect = () => ({ x: x, y: низ - 20, left: x, top: низ - 20, right: x + 60, bottom: низ, width: 60, height: 20 });
    где[n] = { left: x + 'px', top: (низ - 12) + 'px' };
  }
  return где;
}

/** Последнее облако на полке и номер узла имени, у которого оно встало (0 — ни у какого). */
