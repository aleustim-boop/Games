  м.нажать('захват-готово');
  м.нажать('захват-онлайн-остаток-да');
  await отпуститьВсё();
  проверка('конец: в новой партии «Готово» шлёт ход', м.сеть.ходы.some(х => х.действие === 'готово'), JSON.stringify(м.сеть.ходы));
