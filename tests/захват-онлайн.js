/* ---------- разбор разметки страницы (как в tests/захват-экран.js) ---------- */

/** Простой разбор тела страницы в поддельный документ: теги, атрибуты в двойных кавычках, текст. */
function собратьРазметку(html, документ) {
  const чистый = html.replace(/<!--[\s\S]*?-->/g, '').replace(/<script[\s\S]*?<\/script>/g, '');
  const найдено = /<body[^>]*>([\s\S]*)<\/body>/.exec(чистый);
  if (!найдено) throw new Error('В странице нет <body>');
  разобратьВ(найдено[1], документ.body, документ);
}

/** Разобрать кусок разметки внутрь узла (поддельный innerHTML теги не разбирает). */
function разобратьВ(html, корень, документ) {
  const образец = /<(\/?)([a-zA-Z][\w-]*)([^>]*?)(\/?)>|([^<]+)/g;
  const ПУСТЫЕ = new Set(['input', 'br', 'img', 'meta', 'link', 'hr']);
  const стек = [корень];
  let м;
  while ((м = образец.exec(html))) {
    if (м[5] !== undefined) {
      if (м[5].trim()) стек[стек.length - 1].appendChild(документ.createTextNode(м[5]));
      continue;
    }
    const тег = м[2].toLowerCase();
    if (м[1] === '/') {
      for (let i = стек.length - 1; i > 0; i--) if (стек[i].tagName === тег.toUpperCase()) { стек.length = i; break; }
      continue;
    }
    const узел = документ.createElement(тег);
    const атр = /([^\s=]+)(?:\s*=\s*"([^"]*)")?/g;
    let а;
    while ((а = атр.exec(м[3]))) узел.setAttribute(а[1], а[2] === undefined ? '' : а[2]);
    стек[стек.length - 1].appendChild(узел);
    if (м[4] !== '/' && !ПУСТЫЕ.has(тег)) стек.push(узел);
  }
}

/* ---------- поддельные часы ---------- */

/** Таймеры песочницы под рукой проверки: время идёт только через прошло(мс). */
function поставитьЧасы(песочница) {
  let сейчас = 0, номер = 0;
  const очередь = [];
  песочница.setTimeout = function (дело, мс) {
    номер++;
    очередь.push({ номер: номер, когда: сейчас + (Number(мс) || 0), дело: дело });
    return номер;
  };
  песочница.clearTimeout = function (н) {
    const где = очередь.findIndex(з => з.номер === н);
    if (где !== -1) очередь.splice(где, 1);
  };
  return {
    прошло(мс) {
      const до = сейчас + мс;
      for (;;) {
        очередь.sort((а, б) => а.когда - б.когда || а.номер - б.номер);
        const з = очередь[0];
        if (!з || з.когда > до) break;
        очередь.shift();
        сейчас = з.когда;
        з.дело();
      }
      сейчас = до;
    }
  };
}

/** Дать доработать обещаниям (ответам поддельной сети). */
function отпустить() { return new Promise(готово => setImmediate(готово)); }

/* ---------- поддельная сеть ---------- */

function сделатьСеть() {
  const сеть = {
    черновики: [],      // { раунд, черновик }
    ходы: [],           // намерения
    столы: [],          // тела создатьКомнату
    журнал: [],         // порядок обращений: 'черновик' | 'ход'
    ответЧерновика: null,
    ответХода: null,
    // Есть «сервер» { партия, место, мост, версия } — отвечают настоящие двери
    // server/игры/захват.js, а принятый ход, как у js/сеть.js, сперва
    // применяется видом (показатьВид) и только потом разрешает обещание.
    сервер: null,
    отправитьЧерновик(раунд, черновик) {
      сеть.черновики.push({ раунд: раунд, черновик: JSON.parse(JSON.stringify(черновик)) });
      сеть.журнал.push('черновик');
      if (сеть.сервер) {
        const с = сеть.сервер;
        return Promise.resolve(СерверЗахвата.принятьЧерновик(с.партия, с.место, Object.assign({ раунд: раунд }, черновик)));
      }
      return Promise.resolve(сеть.ответЧерновика || { принято: true, черновик: черновик });
    },
    отправитьХод(намерение) {
      сеть.ходы.push(JSON.parse(JSON.stringify(намерение)));
      сеть.журнал.push('ход');
      if (сеть.сервер) {
        const с = сеть.сервер;
        const ответ = СерверЗахвата.сделатьХод(с.партия, с.место, намерение);
        if (ответ.принято) с.мост.показатьВид(видДля(с.партия, с.место, ++с.версия));
        return Promise.resolve(ответ);
      }
      return Promise.resolve(сеть.ответХода || { принято: true });
    },
    создатьКомнату(стол) {
      сеть.столы.push(JSON.parse(JSON.stringify(стол)));
      return Promise.resolve({ ок: true });
    }
  };
  return сеть;
}

/* ---------- мир: страница + настоящие модули ---------- */

const исходникМодуля = fs.readFileSync(ФАЙЛ_МОДУЛЯ, 'utf8');
const исходникСтраницы = fs.readFileSync(path.join(КОРЕНЬ, 'захват.html'), 'utf8');
// Модули страницы, без которых стол и лобби не живут, — в порядке страницы.
const ЧАСТИ_ДО_МОДУЛЯ = ['захват-карты.js', 'захват-правила.js', 'захват-карта-вид.js', 'захват-стол.js', 'онлайн-лобби.js'];

function мир() {
  const документ = сделатьДокумент();
  собратьРазметку(исходникСтраницы, документ);
  const р = поднять('', { память: сделатьПамять(false), документ: документ });
  const часы = поставитьЧасы(р.песочница);
  const сеть = сделатьСеть();
  р.окно.Сеть = сеть;
  for (const часть of ЧАСТИ_ДО_МОДУЛЯ) {
    vm.runInContext(fs.readFileSync(path.join(КОРЕНЬ, 'js', часть), 'utf8'), р.песочница, { filename: 'js/' + часть });
  }
  vm.runInContext(исходникМодуля, р.песочница, { filename: ФАЙЛ_МОДУЛЯ });
  const м = {
    окно: р.окно, документ: документ, часы: часы, сеть: сеть,
    Правила: р.спросить('window.ЗахватПравила'),
    КартаВид: р.спросить('window.ЗахватКартаВид'),
    узел: id => документ.getElementById(id),
    видна: у => !!у && !у.classList.contains('скрыт')
  };
  м.мост = р.окно.ИграПоСети;
  м.модуль = р.окно.ЗахватОнлайн;
  м.лобби = р.окно.ОнлайнЛобби;
  if (!м.мост || !м.модуль) throw new Error('Модуль не поставил window.ИграПоСети или window.ЗахватОнлайн');
  return м;
}

/* ---------- вид партии от настоящего сервера ---------- */

const ИГРОКИ = ['а', 'б', 'в'];
const ИМЕНА = { а: 'Аня', б: 'Боря', в: 'Вера' };

function новаяПартия(раундов) {
  return СерверЗахвата.раздать(null, { игроки: ИГРОКИ, люди: ИГРОКИ, раундовЗахвата: раундов, хозяин: 'а' });
}

function видДля(партия, место, версия) {
  return СерверЗахвата.видДляИгрока(партия, место, {
    код: 'К7', этап: 'игра', версия: версия, сыграноПартий: 0,
    участники: ИГРОКИ.map(к => ({ ключ: к, имя: ИМЕНА[к] }))
  });
}

/** Тот же вид, но следующий раунд: сервер разбирает раунд по таймеру, здесь хватает номера. */
function видСледующегоРаунда(вид) {
  const новый = JSON.parse(JSON.stringify(вид));
  новый.версия = вид.версия + 1;
  новый.захват.раунд = вид.захват.раунд + 1;
  новый.захват.мойЧерновик = { расстановка: {}, приказы: [], составилБот: false };
  новый.захват.яГотов = false;
  return новый;
}

/** Своя область для правок — первая, где хозяин «я». */
function мояОбласть(вид) {
  const з = вид.захват;
  const где = з.хозяева.findIndex((х, н) => н > 0 && х === з.я);
  if (где === -1) throw new Error('В виде нет ни одной своей области');
  return где;
}

/* ---------- 1. показатьВид рисует стол ---------- */

async function проверитьРисование() {
  const м = мир();
  const партия = новаяПартия(20);
  const вид = видДля(партия, 'а', 1);
  м.мост.показатьВид(вид);
  проверка('рисование: экран игры показан', м.узел('экран-игры').classList.contains('экран--виден'));
  проверка('рисование: лобби спрятано', !м.узел('экран-лобби').classList.contains('экран--виден'));
  проверка('рисование: «Раунд N из M» по виду сервера',
    м.узел('захват-раунд').textContent === 'Раунд ' + вид.захват.раунд + ' из ' + вид.захват.всегоРаундов && вид.захват.всегоРаундов === 20,
    м.узел('захват-раунд').textContent);
  проверка('рисование: «Готовы 0/3»', м.узел('захват-готовы').textContent === 'Готовы 0/3', м.узел('захват-готовы').textContent);

  const фишки = м.узел('захват-игроки').children.filter ? м.узел('захват-игроки').children : Array.from(м.узел('захват-игроки').children);
  const видимые = фишки.filter(м.видна);
  проверка('рисование: в полосе видно столько фишек, сколько игроков', видимые.length === ИГРОКИ.length, 'видно ' + видимые.length);
  const имена = видимые.map(ф => (ф.querySelectorAll('.захват-игрок__имя')[0] || {}).textContent);
  // Себя стол зовёт «Вы», соперников — именами из вида сервера.
  проверка('рисование: имена в полосе — из вида сервера', имена.join(',') === 'Вы,Боря,Вера', имена.join(','));
  проверка('рисование: своя фишка помечена', !!видимые[0] && видимые[0].classList.contains('захват-игрок--я'));

  const шайбы = м.узел('захват-слой').querySelectorAll('.захват-шайба');
  const ожидается = м.КартаВид.собратьРаскладку(м.модуль.партияИзВида(вид.захват), { ширина: 358 }).шайбы.length;
  проверка('рисование: шайбы есть и их столько, сколько в раскладке карты', шайбы.length > 0 && шайбы.length === ожидается,
    'шайб ' + шайбы.length + ', в раскладке ' + ожидается);
  const неТе = шайбы.filter(ш => {
    const область = Number(ш.getAttribute('data-область'));
    const число = ш.querySelectorAll('.захват-шайба__число')[0];
    return !число || число.textContent !== String(вид.захват.войска[область]);
  });
  проверка('рисование: число на каждой шайбе — войска из вида', шайбы.length > 0 && неТе.length === 0, 'не совпало ' + неТе.length);

  // Соперник нажал «Готово» — тот же раунд, новая версия: ✓ видна, свой черновик цел.
  const стол = м.модуль.стол();
  const обл = мояОбласть(вид);
  стол.поставитьВойска(обл, 1);
  партия.готовКто.б = 'сам';
  м.мост.показатьВид(видДля(партия, 'а', 2));
  проверка('рисование: «Готовы 1/3» после чужого ✓', м.узел('захват-готовы').textContent === 'Готовы 1/3', м.узел('захват-готовы').textContent);
  проверка('рисование: чужой ✓ не стирает свой черновик', стол.черновик().расстановка[обл] === 1, JSON.stringify(стол.черновик()));

  // Опоздавший вид (версия меньше) не перерисовывает свежий.
  м.мост.показатьВид(видДля(новаяПартия(10), 'а', 1));
  проверка('рисование: опоздавший вид не перерисовал стол', /из 20$/.test(м.узел('захват-раунд').textContent), м.узел('захват-раунд').textContent);
}

/* ---------- 2. пять правок за 300 мс — один запрос ---------- */

async function проверитьЗадержку() {
  const м = мир();
  const вид = видДля(новаяПартия(15), 'а', 1);
  м.мост.показатьВид(вид);
  const стол = м.модуль.стол();
  const обл = мояОбласть(вид);
  const задержка = м.Правила.ЧИСЛА.задержкаЧерновикаМс;
  const правки = [
    () => стол.поставитьВойска(обл, 1),
    () => стол.поставитьВойска(обл, 1),
    () => стол.отменить(),
    () => стол.поставитьВойска(обл, 1),
    () => стол.поставитьВойска(обл, 1)
  ];
  const итоги = [];
  правки.forEach((правка, н) => {
    if (н) м.часы.прошло(60);
    итоги.push(правка());
  });
  проверка('задержка: все 5 правок приняты столом', итоги.every(и => и && и.принято), JSON.stringify(итоги));
  проверка('задержка: сразу после правок запросов нет', м.сеть.черновики.length === 0, 'запросов ' + м.сеть.черновики.length);
  м.часы.прошло(задержка - 1);
  проверка('задержка: за миг до ' + задержка + ' мс тишины запросов нет', м.сеть.черновики.length === 0, 'запросов ' + м.сеть.черновики.length);
  м.часы.прошло(1);
  await отпустить();
  проверка('задержка: 5 правок за 300 мс — один запрос', м.сеть.черновики.length === 1, 'запросов ' + м.сеть.черновики.length);
  const ушло = м.сеть.черновики[0] || { черновик: { расстановка: {} } };
  проверка('задержка: ушла последняя правка', ушло.черновик.расстановка[обл] === 3, JSON.stringify(ушло.черновик));
  проверка('задержка: с номером текущего раунда', ушло.раунд === вид.захват.раунд, 'раунд ' + ушло.раунд);
  м.часы.прошло(задержка * 5);
  await отпустить();
  проверка('задержка: без новых правок новых запросов нет', м.сеть.черновики.length === 1, 'запросов ' + м.сеть.черновики.length);
}

/* ---------- 3. черновик старого раунда выбрасывается ---------- */

async function проверитьСтарыйРаунд() {
  const м = мир();
  const вид = видДля(новаяПартия(15), 'а', 1);
  м.мост.показатьВид(вид);
  const обл = мояОбласть(вид);
  м.модуль.стол().поставитьВойска(обл, 2);
  м.часы.прошло(100);
  const вид2 = видСледующегоРаунда(вид);
  м.мост.показатьВид(вид2);
  проверка('старый раунд: на экране уже раунд 2', /^Раунд 2 /.test(м.узел('захват-раунд').textContent), м.узел('захват-раунд').textContent);
  м.часы.прошло(м.Правила.ЧИСЛА.задержкаЧерновикаМс * 3);
  await отпустить();
  const старые = м.сеть.черновики.filter(з => з.раунд === вид.захват.раунд);
  проверка('старый раунд: правка прошлого раунда не ушла со старым номером', старые.length === 0, JSON.stringify(м.сеть.черновики));
  проверка('старый раунд: смена раунда сама черновик не шлёт', м.сеть.черновики.length === 0, 'запросов ' + м.сеть.черновики.length);
  проверка('старый раунд: на новом раунде черновик пустой', Object.keys(м.модуль.стол().черновик().расстановка).length === 0,
    JSON.stringify(м.модуль.стол().черновик()));
  м.модуль.стол().поставитьВойска(обл, 1);
  м.часы.прошло(м.Правила.ЧИСЛА.задержкаЧерновикаМс);
  await отпустить();
  проверка('старый раунд: правка нового раунда ушла с новым номером',
    м.сеть.черновики.length === 1 && м.сеть.черновики[0].раунд === 2 && м.сеть.черновики[0].черновик.расстановка[обл] === 1,
    JSON.stringify(м.сеть.черновики));
}

/* ---------- 4. отказ «Раунд уже разыгран» — тихо ---------- */

async function проверитьТихийОтказ() {
  const партия = новаяПартия(15);
  const причинаСервера = СерверЗахвата.сделатьХод(партия, 'а', { действие: 'готово', раунд: 999 }).причина;
  проверка('отказ: сервер отвечает «Раунд уже разыгран»', причинаСервера === 'Раунд уже разыгран', причинаСервера);

  const м = мир();
  const вид = видДля(партия, 'а', 1);
  м.мост.показатьВид(вид);
  const подсказка = м.узел('захват-подсказка');
  const обл = мояОбласть(вид);
  м.сеть.ответЧерновика = { принято: false, причина: причинаСервера, устарел: true };
  м.модуль.стол().поставитьВойска(обл, 1);
  м.часы.прошло(м.Правила.ЧИСЛА.задержкаЧерновикаМс);
  await отпустить();
  проверка('отказ: черновик дошёл до сети', м.сеть.черновики.length === 1, 'запросов ' + м.сеть.черновики.length);
  проверка('отказ: «Раунд уже разыгран» не показан', подсказка.textContent.indexOf(причинаСервера) === -1, подсказка.textContent);
  проверка('отказ: подсказка не в виде отказа', !подсказка.classList.contains('захват-подсказка--отказ'));

  // Тот же путь с другим отказом обязан говорить — иначе тишина выше ничего не доказывает.
  const другая = 'Столько войск сюда не поставить';
  м.сеть.ответЧерновика = { принято: false, причина: другая };
  м.модуль.стол().поставитьВойска(обл, 1);
  м.часы.прошло(м.Правила.ЧИСЛА.задержкаЧерновикаМс);
  await отпустить();
  проверка('отказ: другой отказ показан словами', подсказка.textContent === другая, подсказка.textContent);
  проверка('отказ: другой отказ — в виде отказа', подсказка.classList.contains('захват-подсказка--отказ'));
}

/* ---------- 5. выбор раундов уходит числом ---------- */

async function проверитьРаунды() {
  const Правила = мир().Правила;
  const м = мир();
  const места = Правила.ЧИСЛА.мест;
  const описание = м.лобби.описание('захват');
  проверка('раунды: игра подключена к онлайн-лобби', !!описание);
  проверка('раунды: места лобби — 2…6, обычно 4, из правил',
    !!описание && описание.мест.мин === места.мин && описание.мест.макс === места.макс && описание.мест.обычно === места.поУмолчанию
      && места.мин === 2 && места.макс === 6 && места.поУмолчанию === 4,
    JSON.stringify(описание && описание.мест));

  await м.модуль.создатьСтол();
  const безВыбора = м.сеть.столы[0] || {};
  проверка('раунды: без выбора уходит «обычно» из правил', безВыбора.раундовЗахвата === Правила.ЧИСЛА.раундов.обычно, JSON.stringify(безВыбора));
  проверка('раунды: стол — компания и открытый', безВыбора.компанией === true && безВыбора.открытый === true && безВыбора.мест === места.поУмолчанию,
    JSON.stringify(безВыбора));

  for (const число of Правила.ЧИСЛА.раундов.варианты) {
    const принят = м.модуль.выбратьРаунды(число);
    await м.модуль.создатьСтол();
    const стол = м.сеть.столы[м.сеть.столы.length - 1] || {};
    проверка('раунды: выбор ' + число + ' принят', принят === true);
    проверка('раунды: выбор ' + число + ' ушёл числом ' + число, стол.раундовЗахвата === число && typeof стол.раундовЗахвата === 'number',
      JSON.stringify(стол));
  }
  проверка('раунды: в правилах ровно 10, 15, 20', Правила.ЧИСЛА.раундов.варианты.join(',') === '10,15,20', Правила.ЧИСЛА.раундов.варианты.join(','));

  м.модуль.выбратьРаунды('10');
  await м.модуль.создатьСтол();
  проверка('раунды: «10» строкой уходит числом 10', м.сеть.столы[м.сеть.столы.length - 1].раундовЗахвата === 10,
    JSON.stringify(м.сеть.столы[м.сеть.столы.length - 1]));

  м.модуль.выбратьРаунды(20);
  for (const мусор of [25, 'abc', null, 0, 15.5, undefined, {}]) {
    проверка('раунды: мусор ' + JSON.stringify(мусор) + ' не принят', м.модуль.выбратьРаунды(мусор) === false);
  }
  await м.модуль.создатьСтол();
  проверка('раунды: после мусора уходит прежний выбор 20', м.сеть.столы[м.сеть.столы.length - 1].раундовЗахвата === 20,
    JSON.stringify(м.сеть.столы[м.сеть.столы.length - 1]));

  // Видимая «Создать игру»: стол создаёт лобби, штатный обработчик гасится.
  const кнопка = м.узел('кнопка-создать-игру');
  проверка('раунды: на странице есть «Создать игру»', !!кнопка);
  if (кнопка) {
    const столовДо = м.сеть.столы.length;
    let погашено = false;
    кнопка.dispatchEvent({ type: 'click', target: кнопка, preventDefault() {}, stopPropagation() {}, stopImmediatePropagation() { погашено = true; } });
    await отпустить();
    проверка('раунды: «Создать игру» создала стол с выбранными раундами',
      м.сеть.столы.length === столовДо + 1 && м.сеть.столы[м.сеть.столы.length - 1].раундовЗахвата === 20, JSON.stringify(м.сеть.столы.slice(столовДо)));
    проверка('раунды: штатный обработчик «Создать игру» погашен', погашено);
  }
}

/* ---------- 6. «Готово»: сперва черновик, потом ход ---------- */

async function проверитьГотово() {
  const м = мир();
  const партияСервера = новаяПартия(15);
  const вид = видДля(партияСервера, 'а', 1);
  м.мост.показатьВид(вид);
  м.сеть.сервер = { партия: партияСервера, место: 'а', мост: м.мост, версия: 1 };
  const стол = м.модуль.стол();
  const обл = мояОбласть(вид);
  const всего = вид.захват.моёПодкрепление.всего;

  // Не всё поставлено — «Готово» спрашивает про остаток своим листом.
  стол.поставитьВойска(обл, 1);
  м.узел('захват-готово').click();
  const лист = м.узел('захват-онлайн-остаток');
  проверка('готово: при остатке показан лист вопроса', м.видна(лист));
  проверка('готово: при остатке ничего не ушло на сервер', м.сеть.ходы.length === 0, JSON.stringify(м.сеть.ходы));
  м.узел('захват-онлайн-остаток-да').click();
  await отпустить();
  await отпустить();
  проверка('готово: лист закрыт', !м.видна(лист));
  проверка('готово: сперва черновик, потом ход', м.сеть.журнал.join(',') === 'черновик,ход', м.сеть.журнал.join(','));
  const черновик = м.сеть.черновики[0] || { черновик: { расстановка: {} } };
  const поставлено = Object.keys(черновик.черновик.расстановка).reduce((с, к) => с + черновик.черновик.расстановка[к], 0);
  проверка('готово: в черновике всё подкрепление', поставлено === всего, 'поставлено ' + поставлено + ' из ' + всего);
  проверка('готово: ход «готово» с номером раунда', JSON.stringify(м.сеть.ходы[0]) === JSON.stringify({ действие: 'готово', раунд: 1 }),
    JSON.stringify(м.сеть.ходы));
  проверка('готово: сервер принял «Готово»', партияСервера.готовКто.а === 'сам', JSON.stringify(партияСервера.готовКто));
  проверка('готово: стол показывает ✓', стол.готов());
  м.часы.прошло(м.Правила.ЧИСЛА.задержкаЧерновикаМс * 3);
  await отпустить();
  проверка('готово: отложенный черновик не догнал «Готово»', м.сеть.черновики.length === 1, 'запросов ' + м.сеть.черновики.length);

  // Сервер говорит «готов» — ✓ держится и на новом виде того же раунда.
  const партия = новаяПартия(15);
  партия.готовКто.а = 'сам';
  const м2 = мир();
  м2.мост.показатьВид(видДля(партия, 'а', 1));
  проверка('готово: ✓ сервера встаёт на стол', м2.модуль.стол().готов());
  проверка('готово: ✓ сервера не шлёт ходов', м2.сеть.ходы.length === 0 && м2.сеть.черновики.length === 0,
    JSON.stringify(м2.сеть.журнал));
}

