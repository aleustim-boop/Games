/* ---------- 17. «вдвоём» — по живым людям, не по числу мест ---------- */

/** Копия вида, где каждому чужому месту (по порядку) применена правка. */
function сПравкойМест(вид, правки) {
  const новый = JSON.parse(JSON.stringify(вид));
  const чужие = новый.захват.игроки.filter(и => и.номер !== новый.захват.я);
  правки.forEach((правка, н) => { if (чужие[н]) Object.assign(чужие[н], правка); });
  return новый;
}

/** Слова окна «Выйти из партии?» по стрелке «‹»; окно закрывается «Остаться». */
