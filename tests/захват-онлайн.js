/** Конец партии от настоящего сервера: последний раунд разобран, в виде итог (ключи — номера мест). */
function партияКонца() {
  const партия = новаяПартия(15);
  const первый = видДля(партия, 'а', 1);
  партия.раунд = партия.всегоРаундов;
  разобрать(партия);
  if (!партия.завершена) throw new Error('Сервер не закончил партию после последнего раунда');
  return { партия: партия, первый: первый };
}

/**
 * Копия вида конца для места (версия растёт — опоздавшим вид не считается).
 * Кто победил, решают боты случайно, поэтому места ставим сами: а — 1-е, б — 2-е,
 * в — 3-е, в плюсе только первый (втроём — один). Остальное поля сервера как есть.
 */
function видКонца(партия, место, версия, правка) {
  const вид = JSON.parse(JSON.stringify(видДля(партия, место, версия)));
  const итог = вид.захват.итог;
  if (итог) {
    const номер = ключ => вид.захват.игроки.find(и => и.имя === ИМЕНА[ключ]).номер;
    итог.места = ИГРОКИ.map((ключ, н) => Object.assign({}, итог.места.find(с => с.кто === номер(ключ)), { место: н + 1 }));
    итог.победители = [номер('а')];
  }
  if (правка) правка(вид);
  return вид;
}

const рекордыВ = м => JSON.parse(м.память.getItem(м.окно.ЗахватПамять.КЛЮЧИ.рекорды) || '[]');
const итогОткрыт = м => !!м.узел('захват-итог').open;
