/** Таймеры песочницы под рукой проверки: время идёт только через прошло(мс). */
function поставитьЧасы(песочница) {
  let сейчас = 0, номер = 0;
  const очередь = [];
  песочница.setTimeout = function (дело, мс) {
    номер++;
    очередь.push({ номер: номер, когда: сейчас + (Number(мс) || 0), дело: дело });
    return номер;
  };
  песочница.clearTimeout = function (н) {
    const где = очередь.findIndex(з => з.номер === н);
    if (где !== -1) очередь.splice(где, 1);
  };
  // Повторяющийся таймер (таймер раунда): после каждого срабатывания встаёт в очередь снова.
  песочница.setInterval = function (дело, мс) {
    номер++;
    очередь.push({ номер: номер, когда: сейчас + (Number(мс) || 0), дело: дело, период: Number(мс) || 1 });
    return номер;
  };
  песочница.clearInterval = песочница.clearTimeout;
  // Date.now идёт по тем же часам: иначе срок таймера раунда не двигался бы вместе с проверкой.
  const началоЧасов = Date.now();
  песочница.Date = class extends Date {
    static now() { return началоЧасов + сейчас; }
  };
  return {
    /** Сколько повторяющихся таймеров сейчас живо. */
    живыхИнтервалов: () => очередь.filter(з => з.период).length,
    прошло(мс) {
      const до = сейчас + мс;
      for (;;) {
        очередь.sort((а, б) => а.когда - б.когда || а.номер - б.номер);
        const з = очередь[0];
        if (!з || з.когда > до) break;
        очередь.shift();
        сейчас = з.когда;
        if (з.период) { з.когда += з.период; очередь.push(з); }
        з.дело();
      }
      сейчас = до;
    }
  };
}

/** Дать доработать обещаниям (ответам поддельной сети). */
function отпустить() { return new Promise(готово => setImmediate(готово)); }

/* ---------- поддельная сеть ---------- */

function сделатьСеть() {
  const сеть = {
    черновики: [],      // { раунд, черновик }
    ходы: [],           // намерения
    столы: [],          // тела создатьКомнату
    журнал: [],         // порядок обращений: 'черновик' | 'ход'
    ответЧерновика: null,
    ответХода: null,
    // Есть «сервер» { партия, место, мост, версия } — отвечают настоящие двери
    // server/игры/захват.js, а принятый ход, как у js/сеть.js, сперва
    // применяется видом (показатьВид) и только потом разрешает обещание.
    сервер: null,
    // держать = true — ответы не приходят, пока проверка не позовёт выпустить(): так виден «ход в пути».
    держать: false,
    придержанные: [],
    покинуто: 0,        // сколько раз звали Сеть.покинутьПартию
    отправитьЧерновик(раунд, черновик) {
      сеть.черновики.push({ раунд: раунд, черновик: JSON.parse(JSON.stringify(черновик)) });
      сеть.журнал.push('черновик');
      return ответить(() => {
        if (сеть.сервер) {
          const с = сеть.сервер;
          return СерверЗахвата.принятьЧерновик(с.партия, с.место, Object.assign({ раунд: раунд }, черновик));
        }
        return сеть.ответЧерновика || { принято: true, черновик: черновик };
      });
    },
    отправитьХод(намерение) {
      сеть.ходы.push(JSON.parse(JSON.stringify(намерение)));
      сеть.журнал.push('ход');
      return ответить(() => {
        if (сеть.сервер) {
          const с = сеть.сервер;
          const ответ = СерверЗахвата.сделатьХод(с.партия, с.место, намерение);
          if (ответ.принято) с.мост.показатьВид(видДля(с.партия, с.место, ++с.версия));
          return ответ;
        }
        return сеть.ответХода || { принято: true };
      });
    },
    покинутьПартию() { сеть.покинуто++; },
    /** Отдать придержанные ответы: подмена — этот ответ всем, иначе — обычный ответ. */
    выпустить(подмена) {
      сеть.придержанные.splice(0).forEach(з => з.готово(подмена !== undefined ? подмена : з.вычислить()));
    },
    создатьКомнату(стол) {
      сеть.столы.push(JSON.parse(JSON.stringify(стол)));
      return Promise.resolve({ ок: true });
    }
  };
  function ответить(вычислить) {
    if (!сеть.держать) return Promise.resolve(вычислить());
    return new Promise(готово => сеть.придержанные.push({ вычислить: вычислить, готово: готово }));
  }
  return сеть;
}

/** Дать доработать цепочкам обещаний в несколько звеньев (черновик → ход → итог). */
async function отпуститьВсё() {
  for (let i = 0; i < 6; i++) await отпустить();
}

