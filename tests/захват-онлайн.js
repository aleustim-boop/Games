/* =====================================================================
   ПРОВЕРКА: «Захват» по сети в браузере (этап В9, js/захват-онлайн.js).

   Запуск:
       node tests/захват-онлайн.js                    — обычный прогон
       node tests/захват-онлайн.js --сломать [ПАПКА]  — ломающий прогон: три порчи
       node tests/захват-онлайн.js --файл КОПИЯ.js    — прогон на копии модуля

   Как устроено. Страница захват.html разбирается в поддельный документ
   (tests/поддельный-браузер.js), в песочницу грузятся настоящие модули
   страницы, которые нужны столу, и сам модуль. Часы поддельные: время
   двигает только проверка. Сеть поддельная: пишет журнал запросов и
   отвечает так, как скажет проверка. Вид партии собирает НАСТОЯЩИЙ
   сервер (server/игры/захват.js, видДляИгрока) — без сети, вызовом.

   Что проверяется:
     1. показатьВид рисует стол: экран игры, «Раунд N из M», «Готовы x/y»,
        полоса игроков с именами, шайбы с войсками по виду сервера;
     2. 5 правок за 300 мс — один запрос, и в нём последняя правка;
     3. правка до смены раунда не уходит со старым номером;
     4. отказ «Раунд уже разыгран» (текст берётся у сервера) — молча,
        другой отказ — словами в подсказке;
     5. выбор 10, 15, 20 доезжает до создатьКомнату числом; мусор не принят;
     6. «Готово» сперва шлёт черновик, потом ход «готово» с номером раунда.

   Ломающий прогон портит КОПИЮ модуля во временной папке (место порчи
   обязано найтись ровно один раз) и требует, чтобы копия покраснела:
     — черновик без задержки (5 правок — 5 запросов);
     — выбор раундов не уходит в настройки стола;
     — черновик старого раунда не выбрасывается.
   Итог: «Поломок: N, покраснело: N».
   ===================================================================== */

