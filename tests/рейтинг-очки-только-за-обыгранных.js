/* =====================================================================
   ОЧКИ ПОБЕДИТЕЛЮ — ТОЛЬКО ЗА ОБЫГРАННЫХ.

   Зачем. Ревьюер сервера 30.09 нашёл: победитель получал очки за
   каждого человека за столом, включая других победителей, хотя
   описание обещает «за каждого обыгранного». В дураке вчетвером с
   одним проигравшим каждый из трёх победителей брал 30 очков вместо
   10. Владелец 30.09 08:21: «очки только за проигравших».

   ЧТО ПРОВЕРЯЕМ:
     1) дурак вчетвером, один проигравший: каждый победитель берёт 10
        (за одного обыгранного), проигравший — 0;
     2) вдвоём — как раньше: 10 и 0; ничья вдвоём — по 5;
     3) пары 2 на 2 — как раньше: победитель 10 + 10 за соперников и 5
        за напарника (напарник не соперник, за него половинная доля);
     4) победа над тем, кто сыграл вничью, — тоже обыгранный: 10;
     5) боты по тому же правилу: бот, который тоже победил, не обыгран.

   Боевых данных не касается: папка данных (GAMES_DATA) — временная.

   УМЕЕТ КРАСНЕТЬ:
     node tests/рейтинг-очки-только-за-обыгранных.js --сломать [папка]
   копирует server/ (без server/данные) и js/игры-реестр.js во временную
   папку (или в названную), в КОПИИ server/рейтинг.js убирает правило
   «только за обыгранных» и гоняет те же проверки на копии — прогон
   обязан провалиться. Файлы проекта не трогаются.

   Запуск: node tests/рейтинг-очки-только-за-обыгранных.js
   Выход 0 — провалов нет.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

const ПРОЕКТ = path.join(__dirname, '..');
const гдеЛомать = process.argv.indexOf('--сломать');
const ЛОМАТЬ = гдеЛомать !== -1;

let всегоПроверок = 0;
let провалов = 0;
function равно(что, было, надо) {
  всегоПроверок++;
  if (было === надо) { console.log('  ок     ' + что + ': ' + было); return; }
  провалов++;
  console.log('  ПРОВАЛ ' + что + ': ' + было + ' (ждали ' + надо + ')');
}

/** Заменить ровно одно вхождение, иначе приём порчи устарел — сказать вслух. */
function заменитьРовноОдин(файл, старое, новое) {
  const части = fs.readFileSync(файл, 'utf8').split(старое);
  if (части.length !== 2) {
    throw new Error('приём порчи устарел: «' + старое + '» встречается в ' + файл + ' ' +
      (части.length - 1) + ' раз(а) вместо одного — поправьте проверку тем же коммитом');
  }
  fs.writeFileSync(файл, части.join(новое), 'utf8');
}

/** Откуда брать код: из проекта или из испорченной копии. */
function кодИзКопииИлиПроекта() {
  if (!ЛОМАТЬ) return ПРОЕКТ;
  const названная = process.argv[гдеЛомать + 1];
  const папка = (названная && названная.indexOf('--') !== 0)
    ? path.resolve(названная)
    : fs.mkdtempSync(path.join(os.tmpdir(), 'рейтинг-за-обыгранных-сломать-'));
  fs.mkdirSync(папка, { recursive: true });
  // Боевые данные в копию не везём — они не нужны и не наши.
  fs.cpSync(path.join(ПРОЕКТ, 'server'), path.join(папка, 'server'), {
    recursive: true,
    filter: function (откуда) {
      const имя = path.basename(откуда);
      return имя !== 'данные' && имя !== 'node_modules';
    }
  });
  fs.mkdirSync(path.join(папка, 'js'), { recursive: true });
  fs.copyFileSync(path.join(ПРОЕКТ, 'js', 'игры-реестр.js'), path.join(папка, 'js', 'игры-реестр.js'));
  // Порча: победителю снова платят за каждого за столом.
  заменитьРовноОдин(path.join(папка, 'server', 'рейтинг.js'),
    "if (исход === 'победа' && !этоНапарник && !обыгран(другой, игрок)) continue;",
    '/* ИСПОРЧЕНО --сломать: платим за каждого за столом */');
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: код из испорченной копии ' + папка + ' — прогон обязан провалиться ***\n');
  return папка;
}

const КОД = кодИзКопииИлиПроекта();
process.env.GAMES_DATA = fs.mkdtempSync(path.join(os.tmpdir(), 'рейтинг-за-обыгранных-данные-'));
const рейтинг = require(path.join(КОД, 'server', 'рейтинг.js'));
const ЗА_ЧЕЛОВЕКА = рейтинг.ЦЕНА.человек;

/** Живой игрок за столом; напарник — номер напарника в паре или ничего. */
function человек(номер, исход, напарник) {
  return { номер: номер, имя: 'И' + номер, этоБот: false,
    победил: исход === 'победа', ничья: исход === 'ничья',
    напарник: напарник === undefined ? null : напарник };
}
function бот(уровень, исход) {
  return { этоБот: true, уровень: уровень, победил: исход === 'победа', ничья: исход === 'ничья' };
}

/** Очки игрока в дураке. */
function очки(номер) {
  const срез = рейтинг.срезДляИгрока('дурак', номер);
  return срез.я ? срез.я.очки : 0;
}

console.log('=== Очки победителю — только за обыгранных ===\n');
console.log('Цена победы над человеком из server/рейтинг.js: ' + ЗА_ЧЕЛОВЕКА.победа);

console.log('\n1. Дурак вчетвером: трое победили, один проиграл');
рейтинг.забытьВсё();
рейтинг.учестьПартию('дурак', [
  человек(101, 'победа'), человек(102, 'победа'), человек(103, 'победа'), человек(104, 'поражение')
]);
равно('победитель 101 — за одного обыгранного', очки(101), ЗА_ЧЕЛОВЕКА.победа);
равно('победитель 102 — за одного обыгранного', очки(102), ЗА_ЧЕЛОВЕКА.победа);
равно('победитель 103 — за одного обыгранного', очки(103), ЗА_ЧЕЛОВЕКА.победа);
равно('проигравший 104', очки(104), 0);

console.log('\n2. Вдвоём — как раньше');
рейтинг.забытьВсё();
рейтинг.учестьПартию('дурак', [человек(201, 'победа'), человек(202, 'поражение')]);
равно('победитель', очки(201), ЗА_ЧЕЛОВЕКА.победа);
равно('проигравший', очки(202), 0);
рейтинг.учестьПартию('дурак', [человек(203, 'ничья'), человек(204, 'ничья')]);
равно('ничья вдвоём, первый', очки(203), ЗА_ЧЕЛОВЕКА.ничья);
равно('ничья вдвоём, второй', очки(204), ЗА_ЧЕЛОВЕКА.ничья);

console.log('\n3. Пары 2 на 2 — как раньше');
рейтинг.забытьВсё();
рейтинг.учестьПартию('дурак', [
  человек(301, 'победа', 303), человек(302, 'поражение', 304),
  человек(303, 'победа', 301), человек(304, 'поражение', 302)
]);
const заПару = ЗА_ЧЕЛОВЕКА.победа * 2 + Math.floor(ЗА_ЧЕЛОВЕКА.победа * 0.5);
равно('победитель 301: два соперника и половина за напарника', очки(301), заПару);
равно('победитель 303: так же', очки(303), заПару);
равно('проигравший 302', очки(302), 0);
равно('проигравший 304', очки(304), 0);

console.log('\n4. Втроём: победа, ничья, поражение');
рейтинг.забытьВсё();
рейтинг.учестьПартию('дурак', [человек(401, 'победа'), человек(402, 'ничья'), человек(403, 'поражение')]);
равно('победитель 401: обыграл и ничейника, и проигравшего', очки(401), ЗА_ЧЕЛОВЕКА.победа * 2);

console.log('\n5. Боты: бот-победитель не обыгран');
рейтинг.забытьВсё();
рейтинг.учестьПартию('дурак', [человек(501, 'победа'), бот('сложный', 'поражение'), бот('обычный', 'победа')]);
равно('501 берёт только за проигравшего сложного', очки(501), рейтинг.ЦЕНА.сложный.победа);

console.log('\nИтого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
process.exit(провалов > 0 ? 1 : 0);
