function поставитьЧасы(песочница) {
  let сейчас = 0, номер = 0;
  const очередь = [];
  песочница.setTimeout = (дело, мс) => { номер++; очередь.push({ номер, когда: сейчас + (Number(мс) || 0), дело }); return номер; };
  песочница.clearTimeout = н => { const где = очередь.findIndex(з => з.номер === н); if (где !== -1) очередь.splice(где, 1); };
  песочница.setInterval = (дело, мс) => { номер++; очередь.push({ номер, когда: сейчас + (Number(мс) || 0), дело, период: Number(мс) || 1 }); return номер; };
  песочница.clearInterval = песочница.clearTimeout;
  const началоЧасов = Date.now();
  песочница.Date = class extends Date { static now() { return началоЧасов + сейчас; } };
  return {
    прошло(мс) {
      const до = сейчас + мс;
      for (;;) {
        очередь.sort((а, б) => а.когда - б.когда || а.номер - б.номер);
        const з = очередь[0];
        if (!з || з.когда > до) break;
        очередь.shift();
        сейчас = з.когда;
        if (з.период) { з.когда += з.период; очередь.push(з); }
        з.дело();
      }
      сейчас = до;
    }
  };
}

