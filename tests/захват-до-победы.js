/**
 * Страница с ботами. ящик — { ключ: строка } заранее в памяти (память живёт между мирами, как между запусками);
 * чужиеРекорды — строки, которые экран увидит как таблицу рекордов (память лишних полей не хранит — см. отчёт).
 * Следилки: новыеПартии (что ушло в новаяПартия), рекорды (что экран отдал в добавитьРекорд), построения.
 */
function мирБотов(ящик, посев, чужиеРекорды) {
  const документ = сделатьДокумент();
  собратьРазметку(исходникСтраницы, документ);
  оживитьОкна(документ);
  const память = сделатьПамять(false);
  for (const ключ of Object.keys(ящик)) память.setItem(ключ, ящик[ключ]);
  const часы = поддельныеЧасы(new Date(2026, 9, 2, 15, 0).getTime());
  const р = поднять('', { память, документ, часы });
  поставитьКартинки(р.окно);
  const таймеры = сделатьТаймеры(часы);
  р.песочница.setTimeout = таймеры.setTimeout;
  р.песочница.clearTimeout = таймеры.clearTimeout;
  const мат = Object.create(Math);
  мат.random = случайСПосевом(посев || 7);
  р.песочница.Math = мат;
  р.окно.Телеграм = {
    показатьСтрелку: () => true, кнопкаНастроек: () => true, отклик: () => {},
    имяИгрока: () => 'Аня', вибрацияДоступна: () => false, вибрацияВключена: () => false, включитьВибрацию: () => {}
  };
  документ.getElementById('захват-карта').clientWidth = 360;
  документ.getElementById('захват-холст').getContext = () => кисть;
  for (const часть of ЧАСТИ_БОТОВ) {
    vm.runInContext(fs.readFileSync(path.join(КОРЕНЬ, 'js', часть), 'utf8'), р.песочница, { filename: 'js/' + часть });
  }
  const м = { окно: р.окно, документ, память, таймеры, ошибки: р.ошибкиКонсоли, новыеПартии: [], рекорды: [], построения: [] };
  // Что ушло в новаяПартия.
  const новаяНастоящая = р.окно.ЗахватПравила.новаяПартия;
  р.окно.ЗахватПравила.новаяПартия = function (настройки) {
    м.новыеПартии.push(JSON.parse(JSON.stringify(настройки)));
    return новаяНастоящая.apply(this, arguments);
  };
  // Что экран пишет в рекорды и что читает из них.
  const открытьНастоящее = р.окно.ЗахватПамять.открытьДляСтраницы;
  р.окно.ЗахватПамять.открытьДляСтраницы = function () {
    const п = открытьНастоящее.apply(this, arguments);
    const добавить = п.добавитьРекорд;
    п.добавитьРекорд = строка => { м.рекорды.push(JSON.parse(JSON.stringify(строка))); return добавить(строка); };
    if (чужиеРекорды) {
      п.рекорды = () => чужиеРекорды;
      п.сводка = () => ({ сыграно: чужиеРекорды.length, побед: 0, лучшийСчёт: 0 });
    }
    return п;
  };
  const построитьНастоящее = р.окно.ЗахватРаскрытие.построить;
  р.окно.ЗахватРаскрытие.построить = function (вход) {
    const итог = построитьНастоящее.apply(this, arguments);
    м.построения.push({ вход, расписание: итог });
    return итог;
  };
  // Поддельный innerHTML теги не разбирает: нижнюю полосу собираем по id кнопок из строки.
  const полоса = документ.querySelector('#экран-лобби .нижние-вкладки');
  if (!полоса) throw new Error('В лобби нет нижней полосы (.нижние-вкладки)');
  const прокси = new Proxy(полоса, {
    set(цель, имя, значение) {
      if (имя !== 'innerHTML') { цель[имя] = значение; return true; }
      цель.childNodes.length = 0;
      const образец = /<button[^>]*?id="([^"]+)"/g;
      let найдено;
      while ((найдено = образец.exec(значение))) {
        const кнопка = документ.createElement('button');
        кнопка.setAttribute('id', найдено[1]);
        кнопка.setAttribute('class', 'нижняя-вкладка');
        цель.appendChild(кнопка);
      }
      return true;
    }
  });
  const места = полоса.parentNode.childNodes;
  места[места.indexOf(полоса)] = прокси;
  vm.runInContext(исходникЭкрана, р.песочница, { filename: ФАЙЛ_ЭКРАНА });
  м.узел = id => документ.getElementById(id);
  м.нажать = id => { const у = м.узел(id); if (!у) throw new Error('Нет узла ' + id); у.click(); };
  м.пилюли = id => (м.узел(id) ? м.узел(id).querySelectorAll('button') : []);
  м.нажатьПилюлю = (id, значение) => {
    const кнопка = м.пилюли(id).filter(к => к.getAttribute('data-значение') === String(значение))[0];
    if (!кнопка) throw new Error('Нет пилюли ' + значение + ' в ' + id);
    кнопка.click();
  };
  м.отмеченная = id => м.пилюли(id).filter(к => к.getAttribute('aria-checked') === 'true').map(к => к.getAttribute('data-значение'));
  м.видна = у => !!у && !у.classList.contains('скрыт');
  м.готово = () => {
    м.нажать('захват-готово');
    if (/^Вы ещё не ударили/.test(м.узел('захват-подсказка').textContent)) м.нажать('захват-готово');
    const остаток = м.узел('захват-остаток');
    if (остаток && !остаток.classList.contains('скрыт')) м.нажать('захват-остаток-да');
  };
  м.сохранение = () => JSON.parse(память.getItem('zahvat-save'));
  return м;
}

const ОПЫТНЫЙ = { 'zahvat-learned': '1' };
const ботыСВыбором = (длина, мест) => Object.assign({}, ОПЫТНЫЙ,
  { 'zahvat-bots': JSON.stringify({ мест: мест || 3, уровень: 'лёгкий', раундовЗахвата: длина }) });

/** Партия с ботами, сыгранная один раунд; её сохранение — основа для «перемотки» на нужный раунд. */
async function сохранениеПослеПервогоРаунда(длина) {
  const м = мирБотов(ботыСВыбором(длина), 7);
  м.нажать('захват-боты');
  м.нажать('захват-начать');
  await дождатьсяКартинок();
  m_готово(м);
  return м.сохранение();
}
function m_готово(м) {
  м.готово();
  const п = м.построения[м.построения.length - 1];
  if (п) м.таймеры.прошло(п.расписание.всегоМс);
}

/** Мир, продолженный с сохранения, где партия «перемотана» на раунд (и, если нужно, переписана). */
async function мирНаРаунде(длина, раунд, потраченоМс) {
  const сохр = await сохранениеПослеПервогоРаунда(длина);
  сохр.партия.раунд = раунд;
  if (потраченоМс !== undefined) сохр.партия.потраченоМс = потраченоМс;
  const м = мирБотов(Object.assign({}, ботыСВыбором(длина), { 'zahvat-save': JSON.stringify(сохр) }), 11);
  м.нажать('захват-продолжить');
  await дождатьсяКартинок();
  return м;
}

