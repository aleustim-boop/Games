/* =====================================================================
   КНОПКА «РЕЙТИНГ» НА ПЯТИ ОДИНОЧНЫХ СТРАНИЦАХ — ПРОВЕРКА БЕЗ БРАУЗЕРА.

   ЗАЧЕМ. На пяти одиночных играх (2048, судоку, блоки, три в ряд,
   змейка) должна появиться кнопка-ссылка «Рейтинг» с id
   «рейтинг-ссылка», ведущая на index.html?рейтинг=<ключ игры>, а
   js/рейтинг-экран.js на главной должен уметь прочитать этот параметр
   из адреса и открыть рейтинг нужной игры. Эта проверка написана ДО
   того, как разработчик сделал этап (штаб/задание тестировщику
   29.09) — она обязана быть красной прямо сейчас: это и есть
   доказательство, что она умеет краснеть.

   Что проверяем:
     1) на каждой из пяти страниц — РОВНО один узел с id
        «рейтинг-ссылка», его href = index.html?рейтинг=<ключ>, где
        ключ взят из js/игры-реестр.js по полю «страница» (тем же
        способом, что и tests/у-каждой-игры-рейтинг.js);
     2) на каждой из пяти страниц порядок подключения скриптов —
        telegram → сеть → игры-реестр → очки-рейтинга → «свой ui-скрипт
        игры» (2048-ui.js / sudoku-ui.js / casual-ui.js) — не нарушен
        (тот же порядок, что проверяет tests/казуальные-рейтинг-счёт.js
        строки 221–231, только этот файл сам находит имя ui-скрипта,
        а не хранит вторую копию списка);
     3) в js/рейтинг-экран.js есть разбор параметра «рейтинг» из
        адреса — простая примета: URLSearchParams рядом с
        .get('рейтинг').

   Запуск:
       node tests/казуальные-кнопка-рейтинг.js
       node tests/казуальные-кнопка-рейтинг.js --корень=<папка>
       node tests/казуальные-кнопка-рейтинг.js --сломать

   Ломающий запуск --сломать делает КОПИЮ проекта (html + js/) во
   временную папку и вырезает в копии blocks.html узел с id
   «рейтинг-ссылка» — проверка по копии обязана покраснеть ровно на
   blocks.html. Пока кнопки нет ни на одной из пяти страниц (как
   сейчас, 29.09, до сдачи разработчика), вырезать нечего — сценарий
   честно печатает «приём порчи неприменим» и не притворяется, что
   проверил порчу.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

const ПРОЕКТ = path.join(__dirname, '..');
const СТРАНИЦЫ = ['2048.html', 'sudoku.html', 'blocks.html', 'match3.html', 'snake.html'];
const СТРАНИЦА_ДЛЯ_ПОРЧИ = 'blocks.html';

/* Текст без html- и js-комментариев — та же примета, что у
   tests/у-каждой-игры-рейтинг.js: закомментированная «на потом»
   кнопка кнопкой не считается. */
function безКомментариев(текст) {
  return текст
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:'"\\])\/\/[^\n]*/g, '$1');
}

/* Скрипты страницы по порядку: только свои js/…, без хвоста ?v=. */
function скриптыСтраницы(html) {
  const список = [];
  const образец = /<script[^>]*\ssrc="(js\/[^"?]+)(?:\?[^"]*)?"/g;
  let найдено;
  while ((найдено = образец.exec(html)) !== null) список.push(найдено[1]);
  return список;
}

/* Все целые теги (открывающий…закрывающий) с данным id — специально
   не только открывающий тег, чтобы --сломать могла вырезать узел
   целиком одним regex'ом. */
function узлыСId(html, id) {
  const рег = new RegExp('<([a-zA-Zа-яА-Я0-9]+)\\b[^>]*\\bid="' + id + '"[^>]*>[\\s\\S]*?<\\/\\1>', 'g');
  const узлы = [];
  let найдено;
  while ((найдено = рег.exec(html)) !== null) узлы.push(найдено[0]);
  return узлы;
}

function href(тег) {
  const м = /\shref="([^"]*)"/.exec(тег);
  return м ? м[1] : null;
}

const НУЖНО_ДО_UI = ['js/telegram.js', 'js/сеть.js', 'js/игры-реестр.js', 'js/очки-рейтинга.js'];

/**
 * Проверить один корень (проект или копию). Возвращает { проверок, провалы }.
 */
function проверитьКорень(КОРЕНЬ, тихо) {
  const итог = { проверок: 0, провалы: [] };
  function сказать(т) { if (!тихо) console.log(т); }
  function проверить(условие, текст) {
    итог.проверок++;
    if (!условие) { итог.провалы.push(текст); сказать('  ПРОВАЛ: ' + текст); }
    else сказать('  ок    : ' + текст);
    return условие;
  }
  function прочитать(относительныйПуть) {
    const полный = path.join(КОРЕНЬ, относительныйПуть);
    return fs.existsSync(полный) ? безКомментариев(fs.readFileSync(полный, 'utf8')) : null;
  }

  let реестр = [];
  try {
    const путь = path.join(КОРЕНЬ, 'js', 'игры-реестр.js');
    delete require.cache[path.resolve(путь)];
    реестр = require(путь).все();
  } catch (ошибка) {
    проверить(false, 'не читается js/игры-реестр.js: ' + ошибка.message);
  }
  проверить(реестр.length > 0, 'реестр игр не пуст');

  let страницНайденоВРеестре = 0;
  СТРАНИЦЫ.forEach(function (файл) {
    сказать('\n--- ' + файл + ' ---');
    const html = прочитать(файл);
    if (!проверить(html !== null, файл + ': файл существует')) return;

    const запись = реестр.find(function (и) { return и.страница === файл; });
    if (!проверить(Boolean(запись), файл + ': есть запись в js/игры-реестр.js с полем «страница» = ' + файл)) return;
    страницНайденоВРеестре++;

    const узлы = узлыСId(html, 'рейтинг-ссылка');
    const ровноОдин = проверить(узлы.length === 1,
      файл + ': ровно один узел id="рейтинг-ссылка" (найдено ' + узлы.length + ')');
    if (узлы.length >= 1) {
      const адрес = href(узлы[0]);
      const ожидаемый = 'index.html?рейтинг=' + запись.ключ;
      проверить(адрес === ожидаемый,
        файл + ': href="' + ожидаемый + '" (пришло ' + JSON.stringify(адрес) + ')');
    } else {
      сказать('  (href не проверить — узла нет)');
    }
    void ровноОдин;

    const скрипты = скриптыСтраницы(html);
    const места = НУЖНО_ДО_UI.map(function (н) { return скрипты.indexOf(н); });
    const естьВсеЧетыре = проверить(места.every(function (м) { return м !== -1; }),
      файл + ': подключены telegram/сеть/реестр/очки-рейтинга ' + JSON.stringify(места));
    const индексUi = скрипты.findIndex(function (с) { return /-ui\.js$/.test(с); });
    const uiНайден = проверить(индексUi !== -1,
      файл + ': найден собственный экранный скрипт вида «…-ui.js» (' +
      (индексUi !== -1 ? скрипты[индексUi] : 'не найден') + ')');
    if (естьВсеЧетыре && uiНайден) {
      const подряд = места.every(function (м, i) { return i === 0 || м > места[i - 1]; }) &&
        индексUi > места[места.length - 1];
      проверить(подряд, файл + ': порядок telegram → сеть → реестр → очки-рейтинга → ui-скрипт не нарушен');
    }
  });
  проверить(страницНайденоВРеестре > 0,
    'ни одна из пяти страниц (2048/судоку/блоки/три-в-ряд/змейка) не нашлась в реестре — проверять нечего');

  сказать('\n--- js/рейтинг-экран.js ---');
  const текстЭкрана = прочитать('js/рейтинг-экран.js');
  if (проверить(текстЭкрана !== null, 'js/рейтинг-экран.js существует')) {
    const примета = /URLSearchParams[\s\S]{0,400}?\.get\(\s*['"]рейтинг['"]\s*\)/;
    проверить(примета.test(текстЭкрана),
      'js/рейтинг-экран.js: есть разбор параметра «рейтинг» из адреса (URLSearchParams + .get(\'рейтинг\'))');
  }

  сказать('\nПроверок: ' + итог.проверок + ', провалов: ' + итог.провалы.length);
  return итог;
}

/* ---------------- Ломающий запуск --сломать ---------------- */

function копияПроекта(имя) {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'казуальные-кнопка-рейтинг-' + имя + '-'));
  fs.readdirSync(ПРОЕКТ).filter(function (ф) { return /\.html$/.test(ф); }).forEach(function (ф) {
    fs.copyFileSync(path.join(ПРОЕКТ, ф), path.join(папка, ф));
  });
  fs.cpSync(path.join(ПРОЕКТ, 'js'), path.join(папка, 'js'), { recursive: true });
  return папка;
}

/* Вырезать узел с данным id целиком (открывающий тег…закрывающий тег).
   Возвращает false, если узла нет вовсе — приём порчи неприменим
   (кнопки ещё не существует), а не «сломать нечего». */
function вырезатьУзел(файл, id) {
  const т = fs.readFileSync(файл, 'utf8');
  const рег = new RegExp('<([a-zA-Zа-яА-Я0-9]+)\\b[^>]*\\bid="' + id + '"[^>]*>[\\s\\S]*?<\\/\\1>');
  if (!рег.test(т)) return false;
  fs.writeFileSync(файл, т.replace(рег, ''), 'utf8');
  return true;
}

function ломающийЗапуск() {
  console.log('Ломающий запуск --сломать: портим КОПИЮ во временной папке, настоящие файлы не трогаем.\n');
  const папка = копияПроекта('а');
  try {
    const вырезано = вырезатьУзел(path.join(папка, СТРАНИЦА_ДЛЯ_ПОРЧИ), 'рейтинг-ссылка');
    if (!вырезано) {
      console.log('ПРИЁМ ПОРЧИ НЕПРИМЕНИМ: в ' + СТРАНИЦА_ДЛЯ_ПОРЧИ + ' нет узла id="рейтинг-ссылка" —');
      console.log('кнопки «Рейтинг» пока нет ни на одной из пяти страниц (это и должен показать обычный запуск без --сломать).');
      console.log('Вырезать нечего. Прогоните --сломать заново, когда разработчик добавит кнопку.');
      process.exit(2);
      return;
    }
    const итог = проверитьКорень(папка, true);
    const провалБлоков = итог.провалы.some(function (п) { return п.indexOf(СТРАНИЦА_ДЛЯ_ПОРЧИ + ':') === 0; });
    console.log(итог.провалы.length ? итог.провалы.join('\n') : '(провалов нет)');
    console.log('');
    if (провалБлоков) {
      console.log('Ломающий запуск покраснел на ' + СТРАНИЦА_ДЛЯ_ПОРЧИ + ', как и должен.');
      process.exit(0);
    } else {
      console.log('ПЛОХО: вырезали кнопку у ' + СТРАНИЦА_ДЛЯ_ПОРЧИ + ', а провала на ней нет — проверка ничего не стережёт.');
      process.exit(1);
    }
  } finally {
    fs.rmSync(папка, { recursive: true, force: true });
  }
}

/* ---------------- Запуск ---------------- */

if (process.argv.indexOf('--сломать') !== -1) {
  ломающийЗапуск();
} else {
  const довод = process.argv.find(function (а) { return а.indexOf('--корень=') === 0; });
  const корень = довод ? path.resolve(довод.slice('--корень='.length)) : ПРОЕКТ;
  const итог = проверитьКорень(корень, false);
  console.log('\nИтого проверок: ' + итог.проверок + ', провалов: ' + итог.провалы.length);
  process.exit(итог.провалы.length ? 1 : 0);
}
