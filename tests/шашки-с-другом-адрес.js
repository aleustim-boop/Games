/* =====================================================================
   ШАШКИ «С ДРУГОМ»: С КАКИМ АДРЕСОМ СЕРВЕРА ИГРА ИДЁТ СОЗДАВАТЬ КОМНАТУ.

   Владелец написал коротко: «в шашках не могу создать игру с другом!!».
   Беда была не в кнопке, а в АДРЕСЕ: в памяти браузера лежал вчерашний
   мёртвый адрес туннеля, а свежий приезжал только ссылкой из бота —
   и на страницу шашек не попадал вовсе.

   Стенд проходит дорогу человека, а не обходную:
       витрина → «Шашки» → «Играть с другом онлайн» → «Создать игру»
   и смотрит не «комната создалась», а НА КАКОЙ АДРЕС ушёл запрос
   «/создать» и что после этого лежит в памяти браузера.

   Пять заходов:
     1. память вчерашняя (мёртвая), ссылка свежая (живая) — обычная
        дорога человека;
     2. то же, но на шашки уходим БЕЗ хвоста ссылки — так делает
        опубликованная версия (в ней переноса хвоста ещё нет);
     3. быстрый палец: сервер отвечает медленно (как настоящий туннель),
        а человек жмёт «Шашки» сразу;
     4. оба адреса живы — память трогать НЕЛЬЗЯ;
     5. закладка: ссылки нет вовсе, в памяти мёртвый адрес — что видит
        человек и не висит ли экран.

   Что нужно запустить заранее:
       node server/сервер.js 8817 --без-памяти     (живой сервер комнат)
       node server/сервер.js 8821 --без-памяти     (второй живой)
       страничный сервер на 8080 (его держит штаб)
   Медленный «туннель» стенд поднимает сам и сам же гасит.

   Запуск:
       node tests/шашки-с-другом-адрес.js 8080 8817 8821
   ===================================================================== */

