/* ------------------------------------------------------------------
   Проверка самого стенда: живы ли те, кого мы считаем живыми
   ------------------------------------------------------------------ */

function постучать(адрес, ждатьМс) {
  return new Promise(function (готово) {
    const запрос = http.get(адрес + encodeURI('/здоровье'), function (ответ) {
      let текст = '';
      ответ.on('data', (кусок) => { текст += кусок; });
      ответ.on('end', function () {
        let данные = null;
        try { данные = JSON.parse(текст); } catch (сбой) { данные = null; }
        готово(Boolean(данные && данные.живой));
      });
    });
    запрос.on('error', () => готово(false));
    запрос.setTimeout(ждатьМс || 3000, function () { запрос.destroy(); готово(false); });
  });
}

/** Войти в комнату по коду — как второй телефон. */
function войтиПоКоду(код) {
  return new Promise(function (готово) {
    const текст = Buffer.from(JSON.stringify({ код: код }), 'utf8');
    const о = http.request({
      host: '127.0.0.1', port: ПОРТ_ЖИВОГО, method: 'POST', path: encodeURI('/войти'),
      headers: { 'Content-Type': 'application/json', 'Content-Length': текст.length }
    }, function (ответ) {
      let к = '';
      ответ.on('data', (ч) => { к += ч; });
      ответ.on('end', function () { try { готово(JSON.parse(к)); } catch (сбой) { готово(null); } });
    });
    о.on('error', () => готово(null));
    о.end(текст);
  });
}

/* ------------------------------------------------------------------
   Медленный «туннель»: стук держит две с половиной секунды,
   всё остальное честно пересылает живому серверу комнат.
   ------------------------------------------------------------------ */

function поднятьМедленный() {
  const сервер = http.createServer(function (запрос, ответ) {
    const общие = {
      'Access-Control-Allow-Origin': запрос.headers.origin || '*',
      'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
      'Access-Control-Allow-Headers': 'Content-Type, bypass-tunnel-reminder',
      'Access-Control-Max-Age': '86400',
      'Vary': 'Origin'
    };
    if (запрос.method === 'OPTIONS') { ответ.writeHead(204, общие); ответ.end(); return; }

    const путь = decodeURIComponent(запрос.url.split('?')[0]);
    const задержка = (путь === '/здоровье') ? ЗАДЕРЖКА_ТУННЕЛЯ : 0;

    let тело = [];
    запрос.on('data', (кусок) => тело.push(кусок));
    запрос.on('end', function () {
      const груз = Buffer.concat(тело);
      setTimeout(function () {
        const наружу = http.request({
          host: '127.0.0.1', port: ПОРТ_ЖИВОГО, method: запрос.method, path: запрос.url,
          headers: {
            'Content-Type': запрос.headers['content-type'] || 'application/json',
            'Content-Length': груз.length
          }
        }, function (свой) {
          const заголовки = Object.assign({}, общие, {
            'Content-Type': свой.headers['content-type'] || 'application/json; charset=utf-8'
          });
          ответ.writeHead(свой.statusCode || 200, заголовки);
          свой.pipe(ответ);
        });
        наружу.on('error', function () {
          ответ.writeHead(502, Object.assign({}, общие, { 'Content-Type': 'application/json; charset=utf-8' }));
          ответ.end('{"ошибка":"живой сервер молчит"}');
        });
        наружу.end(груз);
      }, задержка);
    });
  });
  return new Promise(function (готово, беда) {
    сервер.on('error', беда);
    сервер.listen(ПОРТ_МЕДЛЕННОГО, '127.0.0.1', () => готово(сервер));
  });
}

/* ------------------------------------------------------------------
   Заход: своё окно браузера со своей памятью
   ------------------------------------------------------------------ */

async function завестиЗаход(браузер, память) {
  const окно = await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
  /* Адрес в память кладём ОДИН раз, при первой загрузке. Иначе он лёг бы
     заново на каждом переходе и затёр бы ровно то освежение памяти,
     ради которого стенд и написан. */
  await окно.addInitScript(function (что) {
    try {
      if (window.localStorage.getItem('стенд:посеяно')) return;
      window.localStorage.setItem('стенд:посеяно', 'да');
      /* Кладём под ОБОИМИ именами: под старым — как у живого игрока,
         пришедшего с прошлой версии, под новым — как у того, кто уже
         поиграл после переезда. Чистим тоже оба. */
      if (что) {
        window.localStorage.setItem('подкидной-дурак:адрес-сервера', что);
        window.localStorage.setItem('server_address', что);
      } else {
        window.localStorage.removeItem('подкидной-дурак:адрес-сервера');
        window.localStorage.removeItem('server_address');
      }
    } catch (сбой) { /* памяти нет — заход всё равно что-то покажет */ }
  }, память || '');

  const страница = await окно.newPage();
  const красные = [];
  const запросы = [];
  /* Стуки в дверь считаем ОТДЕЛЬНО и следим не за отправкой, а за ответом.
     Разница решающая: «запрос ушёл» ещё ничего не значит — память
     освежается, когда ответ пришёл. Мерка, не дождавшаяся ответа,
     показала бы «память не менялась» и там, где всё в порядке,
     и там, где сломано. */
  const стук = { ушло: 0, ответило: 0 };
  const отказы = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', function (м) {
    if (м.type() === 'error') красные.push('консоль: ' + м.text());
  });
  function этоСтук(з) {
    let адрес = з.url();
    try { адрес = decodeURIComponent(адрес); } catch (сбой) { /* оставим как есть */ }
    return адрес.indexOf('/здоровье') !== -1;
  }
  страница.on('request', function (з) {
    let адрес = з.url();
    try { адрес = decodeURIComponent(адрес); } catch (сбой) { /* оставим как есть */ }
    запросы.push({ адрес: адрес, метод: з.method(), когда: Date.now() });
    if (адрес.indexOf('/здоровье') !== -1) стук.ушло++;
  });
  страница.on('requestfinished', function (з) { if (этоСтук(з)) стук.ответило++; });
  страница.on('requestfailed', function (з) {
    if (этоСтук(з)) стук.ответило++;
    /* Каждый неудавшийся запрос записываем ВМЕСТЕ С АДРЕСОМ. Без адреса
       «красная строка в консоли» ничего не значит: часть из них наводит
       сам стенд (он нарочно не пускает настоящий скрипт Telegram),
       часть — законный стук в мёртвый адрес. Разобрать это можно
       только по адресу. */
    let адрес = з.url();
    try { адрес = decodeURIComponent(адрес); } catch (сбой) { /* оставим как есть */ }
    const беда = з.failure() ? з.failure().errorText : 'неизвестно';
    отказы.push(беда + '  ←  ' + адрес);
  });
  await подготовитьПодделку(страница, { версия: '7.10' });
  return { окно, страница, красные, запросы, стук, отказы };
}

/** Что сейчас лежит в памяти браузера. */
function памятьСтраницы(страница) {
  return страница.evaluate(function (ключ) {
    try { return window.localStorage.getItem(ключ) || ''; } catch (сбой) { return '(память запрещена)'; }
  }, КЛЮЧ_АДРЕСА);
}

/**
 * Ждём, пока память УСПОКОИТСЯ. Успокоилась — это два условия сразу:
 *   1) оба стука в дверь получили ответ (иначе спор ещё идёт, и «память
 *      не менялась» — это не результат, а просто «ещё рано»);
 *   2) значение не меняется три замера подряд.
 * Ждать просто по часам нельзя: на занятой машине стук идёт дольше,
 * и мерка попала бы в середину разговора с сервером.
 */
async function дождатьсяПокояПамяти(заход, потолокМс) {
  const страница = заход.страница;
  const начало = Date.now();
  const потолок = потолокМс || 12000;
  // Сначала — ответы на стуки. Ждём, пока стуки вообще начнутся и все ответят.
  while (Date.now() - начало < потолок) {
    if (заход.стук.ушло >= 2 && заход.стук.ответило >= заход.стук.ушло) break;
    await спать(50);
  }
  let прежнее = await памятьСтраницы(страница);
  let одинаковых = 0;
  let сменилось = 0;
  while (Date.now() - начало < потолок) {
    await спать(100);
    const сейчас = await памятьСтраницы(страница);
    if (сейчас === прежнее) {
      одинаковых++;
      if (одинаковых >= 3) break;
    } else {
      одинаковых = 0;
      сменилось = Date.now() - начало;
      прежнее = сейчас;
    }
  }
  return { значение: прежнее, мсДоСмены: сменилось, стуков: заход.стук.ушло, ответов: заход.стук.ответило };
}

/** Виден ли узел человеку (есть место на экране и он не спрятан). */
function видно(страница, примета) {
  return страница.evaluate(function (имя) {
    const узел = document.getElementById(имя);
    if (!узел) return false;
    const место = узел.getBoundingClientRect();
    if (место.width < 1 || место.height < 1) return false;
    const вид = window.getComputedStyle(узел);
    return вид.display !== 'none' && вид.visibility !== 'hidden' && Number(вид.opacity) > 0.05;
  }, примета);
}

/** Сколько миллисекунд прошло до того, как узел стал виден. */
async function ждатьВидимости(страница, примета, потолокМс) {
  const начало = Date.now();
  while (Date.now() - начало < (потолокМс || 5000)) {
    if (await видно(страница, примета)) return Date.now() - начало;
    await спать(20);
  }
  return -1;
}

/** Текст узла, если он виден; иначе пусто. */
function текстУзла(страница, примета) {
  return страница.evaluate(function (имя) {
    const узел = document.getElementById(имя);
    if (!узел) return '';
    const вид = window.getComputedStyle(узел);
    if (вид.display === 'none' || вид.visibility === 'hidden') return '';
    return (узел.textContent || '').trim();
  }, примета);
}

/** Куда ушёл запрос с таким путём: список адресов серверов. */
function кудаУшло(запросы, путь) {
  const куда = [];
  for (const з of запросы) {
    if (з.адрес.indexOf(путь) === -1) continue;
    const корень = з.адрес.slice(0, з.адрес.indexOf(путь));
    if (куда.indexOf(корень) === -1) куда.push(корень);
  }
  return куда;
}

/** Понятное имя адреса — чтобы в отчёте не читать числа портов. */
function имяАдреса(адрес) {
  if (адрес === ЖИВОЙ) return 'живой ' + ПОРТ_ЖИВОГО;
  if (адрес === ВТОРОЙ) return 'второй живой ' + ПОРТ_ВТОРОГО;
  if (адрес === МЕДЛЕННЫЙ) return 'медленный туннель ' + ПОРТ_МЕДЛЕННОГО;
  if (адрес === МЁРТВЫЙ) return 'мёртвый ' + ПОРТ_МЁРТВОГО;
  return адрес || '(пусто)';
}

/** Открыть витрину со ссылкой и дождаться, когда видна плитка «Шашки». */
async function открытьВитрину(заход, ссылка) {
  const адрес = САЙТ + '/index.html' + (ссылка ? '?сервер=' + ссылка : '');
  заход.пуск = Date.now();
  await заход.страница.goto(адрес, { waitUntil: 'domcontentloaded' });
  const ждали = await ждатьВидимости(заход.страница, 'кнопка-игра-шашки', 8000);
  return ждали;
}

/** Через сколько после открытия страницы игра впервые постучалась в сервер. */
function когдаПервыйСтук(заход) {
  for (const з of заход.запросы) {
    if (з.адрес.indexOf('/здоровье') !== -1) return з.когда - заход.пуск;
  }
  return -1;
}

/** Дождаться, пока адрес страницы станет страницей шашек. */
async function дождатьсяШашек(страница, потолокМс) {
  const начало = Date.now();
  while (Date.now() - начало < (потолокМс || 8000)) {
    let адрес = страница.url();
    try { адрес = decodeURIComponent(адрес); } catch (сбой) { /* и так сойдёт */ }
    if (адрес.indexOf('шашки.html') !== -1) return адрес;
    await спать(50);
  }
  return '';
}

/** Пройти «Играть с другом онлайн» → «Создать игру» и вернуть, что вышло. */
async function создатьИгру(страница) {
  /* Страница шашек теперь открывается на лобби — прежний «#кнопка-с-другом»
     лежит на запасном спрятанном экране «экран-режимов», напрямую его
     не нажать. Карточка лобби «Играть с другом онлайн» (id «лобби-друг»)
     сама жмёт эту скрытую кнопку — см. js/шашки-лобби.js. */
  await страница.click('#лобби-друг');
  // «Экран рисуется сразу» — меряем, через сколько видна кнопка «Создать игру».
  const доЭкрана = await ждатьВидимости(страница, 'кнопка-создать-игру', 6000);
  if (доЭкрана < 0) return { доЭкрана: -1, код: '', беда: 'экран «Игра с другом» так и не появился' };

  const нажали = Date.now();
  await страница.click('#кнопка-создать-игру');

  // Ждём одного из двух: код комнаты или объяснение, почему нельзя.
  let код = '';
  let беда = '';
  while (Date.now() - нажали < 15000) {
    код = await страница.evaluate(function () {
      const узел = document.getElementById('код-комнаты');
      if (!узел || узел.classList.contains('код-игры--ждём')) return '';
      return (узел.textContent || '').trim();
    });
    if (код) break;
    беда = (await текстУзла(страница, 'нет-сервера-главное')) ||
           (await текстУзла(страница, 'сообщение-друга'));
    if (беда) break;
    await спать(100);
  }
  return { доЭкрана: доЭкрана, код: код, беда: беда, мс: Date.now() - нажали };
}

