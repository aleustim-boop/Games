/*
  Проверка Р22: понятные строки журнала «Захвата» (js/захват-раскрытие.js).
  Что проверяет:
    - журнал: строка края подробная («Край «Кряж» (Пик, Ледник, Перевал, Утёс) теперь целиком у Бота 2: +2 войска в раунд»),
      потерянный край — «Край «Кряж» потерян — у вас уже не все его области (…): −2 войска в раунд»;
    - пластина: прежняя короткая строка края (≤ 36 знаков, без слова «целиком»);
    - строка захвата дописывает «Переведённое сюда 1 войско погибло…» / «Переведённые сюда 3 войска погибли…»;
      перевод НОВОГО хозяина не считается;
    - пластина: «Встреча в пути: Вы −5, Бот 1 −6» / «Встреча в пути: без потерь», слов «Встречный бой» нет нигде.
  Запуск:
    node tests/захват-журнал-понятно.js                     — проверка настоящего файла
    node tests/захват-журнал-понятно.js --файл <путь>       — проверка другой копии файла раскрытия
    node tests/захват-журнал-понятно.js --сломать           — портит КОПИИ во временной папке; каждая порча обязана покраснеть
  Печатает «Итого проверок: N, провалов: M»; при провале выход 1.
*/
const fs = require('fs');
const os = require('os');
const путь = require('path');
const { spawnSync } = require('child_process');

const корень = путь.join(__dirname, '..');
const настоящий = путь.join(корень, 'js', 'захват-раскрытие.js');
const аргументы = process.argv.slice(2);
const иФайл = аргументы.indexOf('--файл');
const файл = иФайл === -1 ? настоящий : путь.resolve(аргументы[иФайл + 1]);

// ---------- ломающий запуск: копии во временной папке, настоящий файл не трогаем ----------
function сломать() {
  const исходник = fs.readFileSync(настоящий, 'utf8');
  const порчи = [
    ['на пластине подробный текст края вместо короткого', 'текст: строкаВзятогоКрая(к, край),', 'текст: подробноВзятогоКрая(к, край),', /пластина/],
    ['в журнал попадает короткая строка края вместо подробной', 'журнал.push(строка.подробно);', 'журнал.push(строка.текст);', /журнал: край называет все области|ваш край|потерянный край/],
    ['перевод нового хозяина считается погибшим', 'д.куда === с.куда && д.кто === с.у ?', 'д.куда === с.куда && д.кто === с.кто ?', /перевод нового хозяина/],
    ['«Встречный бой:» вместо «Встреча в пути:»', "'Встреча в пути: ' + части.join(', ') : 'Встреча в пути: без потерь'", "'Встречный бой: ' + части.join(', ') : 'Встречный бой: без потерь'", /Встреча в пути|Встречный бой/],
    ['потерянный край не начинается с «Край «»', "'Край «' + край.название + '» потерян — у вас", "'Потерян край «' + край.название + '» — у вас", /потерянный край/],
    ['«Переведённые» всегда в единственном числе', "(одно ? 'погибло' : 'погибли')", "'погибло'", /3 войска/],
    ['у взятого края пропали названия областей', "'» (' + областиКраяСловами(к, край.области) + ') теперь целиком '", "'» теперь целиком '", /называет все области|ваш край/],
    ['у потерянного края пропали названия областей', "областиКраяСловами(к, край.все) + '): '", "'): '", /потерянный край/]
  ];
  const папка = fs.mkdtempSync(путь.join(os.tmpdir(), 'захват-журнал-понятно-'));
  let плохих = 0;
  порчи.forEach(function (п, н) {
    if (!исходник.includes(п[1])) { плохих++; console.log('  ПРОВАЛ — порча «' + п[0] + '»: нечего портить, узел не найден'); return; }
    const копия = путь.join(папка, 'копия-' + (н + 1) + '.js');
    fs.writeFileSync(копия, исходник.replace(п[1], п[2]));
    const р = spawnSync(process.execPath, [__filename, '--файл', копия], { encoding: 'utf8' });
    const красные = (р.stdout || '').split('\n').filter(л => л.indexOf('ПРОВАЛ') !== -1);
    const своими = красные.some(л => п[3].test(л));
    if (р.status === 1 && красные.length > 0 && своими) {
      console.log('  порча «' + п[0] + '»: покраснела (' + красные.length + ' строк)');
    } else {
      плохих++;
      console.log('  ПРОВАЛ — порча «' + п[0] + '»: ' + (красные.length ? 'покраснели не те строки: ' + красные.join(' / ') : 'проверка не покраснела'));
    }
  });
  console.log('Порч, на которых проверка не покраснела: ' + плохих);
  console.log('Итого проверок: ' + порчи.length + ', провалов: ' + плохих);
  process.exit(плохих ? 1 : 0);
}
if (аргументы.indexOf('--сломать') !== -1) сломать();

// ---------- сама проверка ----------
// Копия файла лежит во временной папке: её «./захват-…» подтягиваем из js проекта.
const Module = require('module');
const старый = Module.prototype.require;
Module.prototype.require = function (имя) {
  if (имя.startsWith('./захват-')) return старый.call(this, путь.join(корень, 'js', имя.slice(2)));
  return старый.call(this, имя);
};
const Р = require(файл);

let всего = 0;
let провалов = 0;
function проверить(что, условие) {
  всего++;
  if (!условие) { провалов++; console.log('  ПРОВАЛ — ' + что); }
}

const имена = { я: 'Вы', b1: 'Бот 1', b2: 'Бот 2' };
const пусто = () => new Array(32).fill(null);
const до = пусто();
const после = пусто();
[1, 2, 3].forEach(н => { до[н] = 'b2'; после[н] = 'b2'; });
до[4] = 'b1'; после[4] = 'b2';
const войскаДо = new Array(32).fill(3);
function вход(доп) {
  return Object.assign({
    раунд: 3, карта: 'остров', имена: имена, я: 'я', хозяеваДо: до, хозяеваПосле: после, войскаДо: войскаДо,
    события: [
      { вид: 'перевод', кто: 'b1', откуда: 5, куда: 4, сколько: 1 },
      { вид: 'удар', кто: 'b2', у: 'b1', куда: 4, откуда: [{ область: 3, сколько: 5 }], сколько: 5, защитников: 3,
        выбитоНападающих: 2, выбитоЗащитников: 3, исход: 'взята', осталось: 3, столица: false }
    ]
  }, доп || {});
}

// Захват с погибшим переводом.
const р = Р.построить(вход());
const взята = р.журнал.find(с => /теперь у Бота 2/.test(с) && /Переведённое/.test(с));
проверить('строка захвата: нет «Переведённое сюда 1 войско погибло вместе с защитниками» в конце (вышло «' + взята + '»)',
  !!взята && /Переведённое сюда 1 войско погибло вместе с защитниками$/.test(взята));
const край = р.журнал.find(с => с.startsWith('Край «'));
проверить('журнал: край называет все области (вышло «' + край + '»)',
  край === 'Край «Кряж» (Пик, Ледник, Перевал, Утёс) теперь целиком у Бота 2: +2 войска в раунд');
проверить('журнал: строка края — последняя в журнале раунда', р.журнал[р.журнал.length - 1] === край);
const пластина = р.итог.join(' | ');
const короткая = р.итог.find(с => с.startsWith('Край «'));
проверить('пластина: строки края нет совсем — а ждали прежнюю короткую (вышло «' + пластина + '»)', !!короткая);
проверить('пластина: строка края длиннее 36 знаков (вышло «' + короткая + '»)', !!короткая && короткая.length <= 36);
проверить('пластина: попало слово «целиком» (вышло «' + пластина + '»)', !/целиком/.test(пластина));

// Несколько переводов: «Переведённые сюда 3 войска погибли».
const в2 = вход();
в2.события.unshift({ вид: 'перевод', кто: 'b1', откуда: 6, куда: 4, сколько: 2 });
проверить('3 войска: нет «Переведённые сюда 3 войска погибли вместе с защитниками»',
  Р.построить(в2).журнал.some(с => /Переведённые сюда 3 войска погибли вместе с защитниками$/.test(с)));

// Перевод нового хозяина не считается.
const в3 = вход();
в3.события[0] = { вид: 'перевод', кто: 'b2', откуда: 5, куда: 4, сколько: 1 };
проверить('перевод нового хозяина не должен дописываться к строке захвата', !Р.построить(в3).журнал.some(с => /Переведённ/.test(с)));

// Без переводов строка как была.
const в4 = вход();
в4.события.shift();
проверить('без переводов: строка захвата не должна говорить про переведённых', !Р.построить(в4).журнал.some(с => /Переведённ/.test(с)));

// Ваш край.
const послеЯ = пусто();
[1, 2, 3, 4].forEach(н => { послеЯ[н] = 'я'; });
const р5 = Р.построить(вход({ хозяеваПосле: послеЯ }));
проверить('ваш край: нет «Край «Кряж» (…) теперь целиком ваш: +2 войска в раунд» (вышло «' + р5.журнал.join(' | ') + '»)',
  р5.журнал.some(с => /^Край «Кряж» \(Пик, Ледник, Перевал, Утёс\) теперь целиком ваш: \+2 войска в раунд$/.test(с)));

// Потерянный край.
const доЯ = пусто();
[1, 2, 3, 4].forEach(н => { доЯ[н] = 'я'; });
const послеП = пусто();
[1, 2, 3].forEach(н => { послеП[н] = 'я'; });
const р6 = Р.построить(вход({ хозяеваДо: доЯ, хозяеваПосле: послеП, события: [] }));
const потерян = р6.журнал.find(с => /потерян/.test(с));
проверить('потерянный край: журнал не «Край «Кряж» потерян — у вас уже не все его области (Пик, Ледник, Перевал, Утёс): −2 войска в раунд» (вышло «' + потерян + '»)',
  !!потерян && /^Край «Кряж» потерян — у вас уже не все его области \(Пик, Ледник, Перевал, Утёс\): −2 войска в раунд$/.test(потерян));
const потерянПластина = р6.итог.find(с => /потерян/.test(с));
проверить('потерянный край: пластина не прежняя короткая строка (вышло «' + потерянПластина + '»)',
  потерянПластина === 'Край «Кряж» потерян: −2 войска в раунд');

// Встреча в пути.
const вс = Р.построить(вход({ события: [{ вид: 'встречный', области: [1, 2], исход: 'обе погибли',
  колонны: [{ кто: 'я', откуда: 1, куда: 2, было: 5, осталось: 0 }, { кто: 'b1', откуда: 2, куда: 1, было: 6, осталось: 0 }] }] }));
const встреча = вс.итог.find(с => /^Встреча в пути/.test(с));
проверить('пластина: нет «Встреча в пути: Вы −5, Бот 1 −6» (вышло «' + встреча + '»)', встреча === 'Встреча в пути: Вы −5, Бот 1 −6');
const без = Р.построить(вход({ события: [{ вид: 'встречный', области: [1, 2], исход: 'разошлись',
  колонны: [{ кто: 'я', откуда: 1, куда: 2, было: 5, осталось: 5 }, { кто: 'b1', откуда: 2, куда: 1, было: 6, осталось: 6 }] }] }));
проверить('без потерь: нет «Встреча в пути: без потерь» (вышло «' + без.итог.join(' | ') + '»)', без.итог.some(с => с === 'Встреча в пути: без потерь'));
проверить('«Встречный бой» остался в итоге или журнале', !JSON.stringify([вс.итог, вс.журнал, без.итог, без.журнал]).includes('Встречный бой'));

console.log('Итого проверок: ' + всего + ', провалов: ' + провалов);
process.exit(провалов ? 1 : 0);
