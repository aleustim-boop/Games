'use strict';

/* =====================================================================
   ПРОВЕРКА ФЛАГА «--без-памяти».

   Что проверяем. Сервер комнат умеет считать знакомых и статистику и
   складывать их на диск, в server/данные/. Когда сервер поднимают ради
   проверки, эти числа портят настоящую статистику владельца, поэтому у
   сервера есть флаг «--без-памяти»: с ним на диск не пишется ничего.
   Здесь мы поднимаем сервер отдельным процессом — ровно так, как его
   поднимает тестировщик, — создаём в нём комнату и смотрим на файлы.

   ПОЧЕМУ ФАЙЛ ПЕРЕПИСАН (важно, не удалять эту заметку).
   Прежняя проверка начинала с того, что УДАЛЯЛА server/данные/статистика.json
   и удаляла его же в конце. А это боевой файл владельца: один запуск
   проверки — и накопленные числа пропадали без копии и без спроса.
   Теперь так:
     • ничего не удаляем и не переписываем без снимка;
     • перед началом снимаем копию всех файлов в server/данные/ (в память
       этого процесса) и возвращаем всё как было — в том числе если
       проверка упала или её прервали с клавиатуры;
     • проверка «с флагом» стала честнее: раньше она требовала, чтобы
       файла НЕ БЫЛО — то есть работала только на пустой машине. Теперь
       она требует, чтобы файлы не изменились НИ НА БАЙТ, и это верно и
       тогда, когда у владельца уже накоплена статистика;
     • проверка «без флага» (04.10) идёт на ОТДЕЛЬНОЙ временной папке:
       сервер получает её через ДАННЫЕ_ИГРЫ, ключ бота мы ему не даём.
       В пустой папке нет записавшихся на турнир и пометок «отправлено»,
       так что письма слать некому, а настоящая server/данные не
       трогается (проверяем, что она не изменилась ни на байт).
       Рядом может работать и настоящий сервер — мы ему не мешаем.
     • «--сломать»: сервер пишет мимо той папки, на которую смотрит
       проверка, — часть 2 обязана покраснеть (код выхода 1).

   Запуск:
       node tests/проверка-без-памяти.js
       node tests/проверка-без-памяти.js 8799     свой порт для проверки

   Ничего в игре не меняет. Библиотек не требует.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const net = require('net');
const os = require('os');
const { spawn } = require('child_process');

const КОРЕНЬ = path.resolve(__dirname, '..');       // корень проекта — от этого файла, а не зашитый
const ПАПКА_ДАННЫХ = path.join(КОРЕНЬ, 'server', 'данные');
const ФАЙЛ_СТАТИСТИКИ = path.join(ПАПКА_ДАННЫХ, 'статистика.json');
const ПОРТ = Number(process.argv.slice(2).map(Number).find(Boolean)) || 8799;
const СЛОМАТЬ = process.argv.includes('--сломать');   // ломающий запуск: часть 2 обязана покраснеть

/* Порты, на которых у нас обычно живёт настоящий сервер комнат.
   Если на любом из них кто-то отвечает — значит, в те же файлы прямо
   сейчас может писать не только наша проверка. */
const ЧУЖИЕ_ПОРТЫ = [8790, 8795, 8796, 8797, 8798].filter((п) => п !== ПОРТ);

const спать = function (мс) { return new Promise(function (f) { setTimeout(f, мс); }); };

let всёХорошо = true;
let всегоПроверок = 0;
let провалов = 0;
function проверить(что, правда) {
  всегоПроверок++;
  if (!правда) провалов++;
  console.log((правда ? '  ок   ' : '  БЕДА ') + что);
  if (!правда) всёХорошо = false;
}

/* ------------------------------------------------------------------ */
/* Снимок папки данных и возврат её как было                           */
/* ------------------------------------------------------------------ */

/** Что лежит в server/данные прямо сейчас: имя → содержимое (или «не было»). */
function снятьСнимок() {
  const снимок = new Map();
  if (!fs.existsSync(ПАПКА_ДАННЫХ)) return снимок;
  for (const имя of fs.readdirSync(ПАПКА_ДАННЫХ)) {
    const полный = path.join(ПАПКА_ДАННЫХ, имя);
    if (!fs.statSync(полный).isFile()) continue;
    снимок.set(имя, fs.readFileSync(полный));
  }
  return снимок;
}

/** Вернуть папку данных ровно в то состояние, что было на снимке. */
function вернутьКакБыло(снимок) {
  if (!fs.existsSync(ПАПКА_ДАННЫХ)) {
    if (снимок.size === 0) return [];
    fs.mkdirSync(ПАПКА_ДАННЫХ, { recursive: true });
  }
  const что_сделали = [];
  // 1. Кладём назад то, что было
  for (const [имя, содержимое] of снимок) {
    const полный = path.join(ПАПКА_ДАННЫХ, имя);
    const сейчас = fs.existsSync(полный) ? fs.readFileSync(полный) : null;
    if (сейчас && сейчас.equals(содержимое)) continue;
    fs.writeFileSync(полный, содержимое);
    что_сделали.push('вернул ' + имя);
  }
  // 2. Убираем то, чего до нас не было (это наши следы, а не владельца)
  for (const имя of fs.readdirSync(ПАПКА_ДАННЫХ)) {
    const полный = path.join(ПАПКА_ДАННЫХ, имя);
    if (!fs.statSync(полный).isFile()) continue;
    if (снимок.has(имя)) continue;
    fs.unlinkSync(полный);
    что_сделали.push('убрал наш след ' + имя);
  }
  return что_сделали;
}

/** Совпадает ли папка данных со снимком байт в байт. */
function сходитсяСоСнимком(снимок) {
  const теперь = снятьСнимок();
  if (теперь.size !== снимок.size) return { сошлось: false, чем: 'файлов стало ' + теперь.size + ' вместо ' + снимок.size };
  for (const [имя, было] of снимок) {
    if (!теперь.has(имя)) return { сошлось: false, чем: 'пропал ' + имя };
    if (!теперь.get(имя).equals(было)) return { сошлось: false, чем: 'изменился ' + имя };
  }
  return { сошлось: true, чем: 'всё на месте' };
}

/* Снимок снимаем сразу и возвращаем его при любом исходе — в том числе
   когда проверку прервали с клавиатуры или она упала на полуслове. */
const СНИМОК = снятьСнимок();
let ужеВернули = false;
function вернутьОдинРаз(повод) {
  if (ужеВернули) return;
  ужеВернули = true;
  const дела = вернутьКакБыло(СНИМОК);
  if (дела.length) console.log('  (' + повод + ': ' + дела.join(', ') + ')');
}
process.on('exit', function () { вернутьОдинРаз('возврат при выходе'); });
process.on('SIGINT', function () { вернутьОдинРаз('прервали с клавиатуры'); process.exit(130); });
process.on('uncaughtException', function (сбой) {
  вернутьОдинРаз('проверка упала');
  console.error('Проверка упала: ' + (сбой && сбой.stack || сбой));
  process.exit(2);
});

