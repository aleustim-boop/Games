/** С флагом: создаём комнату и ждём — на диске не должно измениться ничего. */
async function сФлагом() {
  console.log('\n=== 1. Запуск «--без-памяти»: на диск не должно уйти ничего ===');
  const { дитя, вывод } = await поднять([String(ПОРТ), '--без-памяти']);
  console.log('  ' + (вывод.split('\n')[0] || ''));
  const комната = await создатьКомнату();
  проверить('комната создана (код ' + (комната && комната.код) + ')', Boolean(комната && комната.код));
  await спать(7000);                         // запись отложена на 5 секунд — ждём с запасом
  const итог = сходитсяСоСнимком(СНИМОК);
  проверить('папка server/данные не изменилась ни на байт — ' + итог.чем, итог.сошлось);
  дитя.kill();
  await спать(600);
  const послеОстановки = сходитсяСоСнимком(СНИМОК);
  проверить('и после остановки сервера тоже — ' + послеОстановки.чем, послеОстановки.сошлось);
}

/** Без флага: файл статистики обязан появиться — но в ОТДЕЛЬНОЙ временной папке.
    Сервер получает её через ДАННЫЕ_ИГРЫ (server/папка-данных.js), поэтому настоящая
    server/данные не трогается, а письма турнира слать некому: в пустой папке
    нет ни записавшихся, ни пометок «отправлено». Ключ бота в окружение не даём. */
async function безФлага() {
  console.log('\n=== 2. Обычный запуск: статистика обязана лечь на диск (во временную папку) ===');
  const ВРЕМЕННАЯ = fs.mkdtempSync(path.join(os.tmpdir(), 'без-памяти-'));
  // «--сломать»: сервер пишет в ДРУГУЮ папку, чем та, на которую смотрит проверка —
  // «файл появился» обязано покраснеть.
  const КУДА_ПИШЕТ = СЛОМАТЬ ? fs.mkdtempSync(path.join(os.tmpdir(), 'без-памяти-мимо-')) : ВРЕМЕННАЯ;
  const окружение = Object.assign({}, process.env, { ДАННЫЕ_ИГРЫ: КУДА_ПИШЕТ });
  delete окружение.BOT_TOKEN;
  delete окружение.GAMES_DATA;
  const ФАЙЛ_ТУТ = path.join(ВРЕМЕННАЯ, 'статистика.json');
  try {
    const { дитя, вывод } = await поднять([String(ПОРТ)], окружение);
    console.log('  ' + (вывод.split('\n')[0] || ''));
    const комната = await создатьКомнату();
    проверить('комната создана (код ' + (комната && комната.код) + ')', Boolean(комната && комната.код));
    await спать(7000);
    проверить('файл статистики появился во временной папке — значит, без флага сервер пишет', fs.existsSync(ФАЙЛ_ТУТ));
    дитя.kill();
    await спать(600);
    const итог = сходитсяСоСнимком(СНИМОК);
    проверить('настоящая server/данные не тронута ни на байт — ' + итог.чем, итог.сошлось);
  } finally {
    fs.rmSync(ВРЕМЕННАЯ, { recursive: true, force: true });
    if (КУДА_ПИШЕТ !== ВРЕМЕННАЯ) fs.rmSync(КУДА_ПИШЕТ, { recursive: true, force: true });
  }
}

