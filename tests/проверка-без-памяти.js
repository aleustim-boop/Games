/* ------------------------------------------------------------------ */

/** С флагом: создаём комнату и ждём — на диске не должно измениться ничего. */
async function сФлагом() {
  console.log('\n=== 1. Запуск «--без-памяти»: на диск не должно уйти ничего ===');
  const { дитя, вывод } = await поднять([String(ПОРТ), '--без-памяти']);
  console.log('  ' + (вывод.split('\n')[0] || ''));
  const комната = await создатьКомнату();
  проверить('комната создана (код ' + (комната && комната.код) + ')', Boolean(комната && комната.код));
  await спать(7000);                         // запись отложена на 5 секунд — ждём с запасом
  const итог = сходитсяСоСнимком(СНИМОК);
  проверить('папка server/данные не изменилась ни на байт — ' + итог.чем, итог.сошлось);
  дитя.kill();
  await спать(600);
  const послеОстановки = сходитсяСоСнимком(СНИМОК);
  проверить('и после остановки сервера тоже — ' + послеОстановки.чем, послеОстановки.сошлось);
}

/** Без флага: файл статистики обязан появиться или измениться. */
async function безФлага() {
  console.log('\n=== 2. Обычный запуск: статистика обязана лечь на диск ===');
  const занятые = [];
  for (const порт of ЧУЖИЕ_ПОРТЫ) if (await портЗанят(порт)) занятые.push(порт);
  if (занятые.length) {
    console.log('  ПРОПУСКАЮ: рядом работает настоящий сервер комнат (порт ' + занятые.join(', ') + ').');
    console.log('  Эта половина проверки пишет в настоящий server/данные/статистика.json,');
    console.log('  и возврат снимка мог бы стереть то, что живой сервер записал в ту же секунду.');
    console.log('  Остановите чужой сервер и запустите проверку снова.');
    return;
  }

  const былоДо = fs.existsSync(ФАЙЛ_СТАТИСТИКИ) ? fs.readFileSync(ФАЙЛ_СТАТИСТИКИ) : null;
  const { дитя, вывод } = await поднять([String(ПОРТ)]);
  console.log('  ' + (вывод.split('\n')[0] || ''));
  const комната = await создатьКомнату();
  проверить('комната создана (код ' + (комната && комната.код) + ')', Boolean(комната && комната.код));
  await спать(7000);
  const сталоПосле = fs.existsSync(ФАЙЛ_СТАТИСТИКИ) ? fs.readFileSync(ФАЙЛ_СТАТИСТИКИ) : null;
  const записалось = сталоПосле !== null && (былоДо === null || !сталоПосле.equals(былоДо));
  проверить('файл статистики появился или изменился — значит, без флага сервер пишет', записалось);
  дитя.kill();
  await спать(600);

  const дела = вернутьКакБыло(СНИМОК);
  console.log('  возврат: ' + (дела.length ? дела.join(', ') : 'возвращать было нечего'));
  const итог = сходитсяСоСнимком(СНИМОК);
  проверить('после проверки папка server/данные ровно такая, какой была — ' + итог.чем, итог.сошлось);
}

/* ------------------------------------------------------------------ */

(async function () {
  console.log('Проверка флага «--без-памяти». Порт для проверки: ' + ПОРТ);
  console.log('Файлы владельца в server/данные: ' +
    (СНИМОК.size ? [...СНИМОК.keys()].join(', ') + ' (снимок снят, вернём как было)' : 'пока пусто'));

  if (await портЗанят(ПОРТ)) {
    console.log('БЕДА: порт ' + ПОРТ + ' занят — возьмите другой: node tests/проверка-без-памяти.js 8798');
    process.exit(2);
  }

  await сФлагом();
  await безФлага();

  вернутьОдинРаз('итоговый возврат');
  const итог = сходитсяСоСнимком(СНИМОК);
  проверить('данные владельца целы — ' + итог.чем, итог.сошлось);

  console.log(всёХорошо ? '\nИТОГ: всё сошлось.' : '\nИТОГ: есть беды.');
  process.exit(всёХорошо ? 0 : 1);
})();
