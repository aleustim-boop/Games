/** Отвечает ли кто-нибудь на этом порту (просто открываем соединение). */
function портЗанят(порт) {
  return new Promise(function (готово) {
    const гнездо = net.connect({ host: '127.0.0.1', port: порт });
    const конец = function (ответ) { гнездо.destroy(); готово(ответ); };
    гнездо.setTimeout(700);
    гнездо.on('connect', function () { конец(true); });
    гнездо.on('timeout', function () { конец(false); });
    гнездо.on('error', function () { конец(false); });
  });
}

function поднять(доводы, окружение) {
  return new Promise(function (готово, беда) {
    const дитя = spawn('node', [path.join(КОРЕНЬ, 'server', 'сервер.js')].concat(доводы),
      окружение ? { env: окружение } : {});
    let вывод = '';
    const срок = setTimeout(function () { дитя.kill(); беда(new Error('сервер не поднялся за 15 секунд')); }, 15000);
    дитя.stdout.on('data', function (кусок) {
      вывод += кусок;
      if (/работает на порту/.test(вывод)) { clearTimeout(срок); готово({ дитя: дитя, вывод: вывод }); }
    });
  });
}

async function создатьКомнату() {
  const ответ = await fetch('http://127.0.0.1:' + ПОРТ + '/создать', {
    method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}'
  }).then(function (о) { return о.json(); });
  return ответ;
}

