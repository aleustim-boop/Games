/* Проверка модели экрана турнира (js/турнир-экран.js) без браузера.
   Запуск: node tests/турнир-экран-модель.js [путь к копии файла экрана]
   Путь доводом нужен ломающему запуску: он портит КОПИЮ, не файл проекта.
   Проверка, нашедшая ноль строк или состояний, краснеет, а не молчит. */
'use strict';

const path = require('path');
const файлЭкрана = process.argv[2] || path.join(__dirname, '..', 'js', 'турнир-экран.js');
const Экран = require(path.resolve(файлЭкрана));

let всего = 0;
let упало = 0;
function проверить(имя, условие, подробность) {
  всего++;
  if (!условие) {
    упало++;
    console.log('КРАСНО  ' + имя + (подробность ? ' — ' + подробность : ''));
  } else {
    console.log('зелено  ' + имя);
  }
}

const НОМЕР_ТЕЛЕГРАМ = 777000111;   // метка: в тексты и строки попасть не должна
const начало = Date.UTC(2026, 9, 5, 17, 0);   // 20:00 МСК
const конец = начало + 30 * 60000;
const ПЛЮС2 = 120;
const ПЛЮС3 = 180;

function вид(состояние, добавка) {
  return Object.assign({
    ид: 'дурак-2026-10-05', игра: 'дурак', началоМс: начало, конецМс: конец,
    состояние: состояние, записалось: 3, записан: false, таблица: []
  }, добавка || {});
}

const таблица = [
  { место: 1, имя: 'Аня', очки: 4, побед: 2, ничьих: 0, поражений: 0, партий: 2, я: false, номер: НОМЕР_ТЕЛЕГРАМ },
  { место: 2, имя: 'Боря', очки: 2, побед: 1, ничьих: 0, поражений: 1, партий: 2, я: true, номер: НОМЕР_ТЕЛЕГРАМ + 1 },
  { место: 3, имя: 'Вика', очки: 0, побед: 0, ничьих: 0, поражений: 2, партий: 2, я: false }
];

function всеТексты(м) {
  return JSON.stringify(м);
}

// --- Нет сети ---
const нет = Экран.модель(null, начало, ПЛЮС2);
проверить('нет вида: «Турнир сейчас недоступен»',
  нет.состояние === 'недоступно' && нет.статус === 'Турнир сейчас недоступен', JSON.stringify(нет));

// --- До начала ---
const до = Экран.модель(вид('запись'), начало - (2 * 3600 + 5 * 60) * 1000, ПЛЮС2);
проверить('запись → состояние «до»', до.состояние === 'до', до.состояние);
проверить('17:00 UTC при +02:00 → «20:00 МСК (у вас 19:00)»', до.время === '20:00 МСК (у вас 19:00)', до.время);
const до3 = Экран.модель(вид('запись'), начало - 1000, ПЛЮС3);
проверить('при +03:00 → «20:00 МСК» без «у вас»', до3.время === '20:00 МСК', до3.время);
проверить('обратный отсчёт «2 ч 05 мин»', до.отсчёт === 'До начала: 2 ч 05 мин', до.отсчёт);
проверить('отсчёт в последнюю минуту — секунды', до3.отсчёт === 'До начала: 1 с', до3.отсчёт);
проверить('не записан → кнопка «Участвую»',
  до.кнопки.length === 1 && до.кнопки[0].ид === 'участвую' && до.кнопки[0].текст === 'Участвую', JSON.stringify(до.кнопки));
проверить('сколько записалось: «Записалось 3 игрока»', до.записалось === 'Записалось 3 игрока', до.записалось);
проверить('записалось 1 и 5 — правильные слова',
  Экран.модель(вид('запись', { записалось: 1 }), начало - 1000, ПЛЮС3).записалось === 'Записался 1 игрок' &&
  Экран.модель(вид('запись', { записалось: 5 }), начало - 1000, ПЛЮС3).записалось === 'Записалось 5 игроков');
проверить('никто не записался — честная строка',
  Экран.модель(вид('запись', { записалось: 0 }), начало - 1000, ПЛЮС3).записалось === 'Пока никто не записался');
const записан = Экран.модель(вид('запись', { записан: true }), начало - 1000, ПЛЮС3);
проверить('записан → «Вы записаны», кнопки нет', записан.статус === 'Вы записаны' && записан.кнопки.length === 0);
проверить('вчерашнего победителя в виде нет — строки нет', до.вчера === '');
const сВчера = Экран.модель(вид('запись', { вчерашнийПобедитель: 'Аня' }), начало - 1000, ПЛЮС3);
проверить('вчерашний победитель, если есть в виде', сВчера.вчера === 'Вчерашний победитель: Аня', сВчера.вчера);

// --- Идёт ---
const идёт = Экран.модель(вид('идёт', { таблица: таблица }), начало + 10 * 60000, ПЛЮС2);
проверить('идёт → состояние «идёт»', идёт.состояние === 'идёт', идёт.состояние);
проверить('идёт: «Ищем соперника…» (ищем = да)', идёт.ищем === true);
проверить('идёт: таблица из 3 строк', идёт.строки.length === 3, String(идёт.строки.length));
const моя = идёт.строки.filter(function (с) { return с.я; });
проверить('идёт: ровно одна строка помечена «я», и это Боря', моя.length === 1 && моя[0].имя === 'Боря', JSON.stringify(моя));
проверить('идёт: отсчёт до конца', идёт.отсчёт === 'До конца: 20 мин 00 с', идёт.отсчёт);

// --- Доигрыш ---
const доигрыш = Экран.модель(вид('доигрыш', { таблица: таблица }), конец + 60000, ПЛЮС2);
проверить('доигрыш → состояние «доигрыш»', доигрыш.состояние === 'доигрыш', доигрыш.состояние);
проверить('доигрыш: «Доигрываются последние партии», пары не ищем',
  доигрыш.статус === 'Доигрываются последние партии' && доигрыш.ищем === false && доигрыш.кнопки.length === 0);

// --- После ---
const после = Экран.модель(вид('окончен', { таблица: таблица }), конец + 20 * 60000, ПЛЮС2);
проверить('окончен → состояние «после», места видны', после.состояние === 'после' && после.строки.length === 3 && после.строки[0].место === 1);
const несостоялся = Экран.модель(вид('окончен', { таблица: [] }), конец + 20 * 60000, ПЛЮС2);
проверить('итог без партий → «В этот раз не набралось соперников»',
  несостоялся.состояние === 'после' && несостоялся.статус === 'В этот раз не набралось соперников' && несостоялся.строки.length === 0);
const флагНет = Экран.модель(вид('окончен', { таблица: таблица, состоялся: false }), конец + 20 * 60000, ПЛЮС2);
проверить('состоялся:false при 3 строках → «не набралось соперников»',
  флагНет.статус === 'В этот раз не набралось соперников' && флагНет.строки.length === 0);
const флагДа = Экран.модель(вид('окончен', { таблица: таблица, состоялся: true }), конец + 20 * 60000, ПЛЮС2);
проверить('состоялся:true → места видны', флагДа.строки.length === 3 && !/не набралось/.test(всеТексты(флагДа)));
проверить('в состоявшемся турнире «не набралось» нет', !/не набралось/.test(всеТексты(после)));
const нетТурнира = Экран.модель(вид('нет турнира'), начало, ПЛЮС2);
проверить('«нет турнира» → «Сегодня турнира нет»', нетТурнира.состояние === 'нет' && нетТурнира.статус === 'Сегодня турнира нет');

проверить('после несостоявшегося — «Приходите на следующий турнир»', несостоялся.следующий === 'Приходите на следующий турнир', несостоялся.следующий);
проверить('после состоявшегося — та же строка о следующем турнире', после.следующий === 'Приходите на следующий турнир', после.следующий);
проверить('до начала строки о следующем турнире нет', до.следующий === '' && идёт.следующий === '');

// --- Склонение ---
const слово = { партия: ['партия', 'партии', 'партий'], игрок: ['игрок', 'игрока', 'игроков'] };
const ждём = [
  [1, 0], [2, 1], [5, 2], [11, 2], [12, 2], [21, 0], [22, 1], [25, 2], [111, 2], [112, 2], [101, 0]
];
for (const имя of ['партия', 'игрок']) {
  const ф = слово[имя];
  for (const п of ждём) {
    const факт = Экран.падеж(п[0], ф[0], ф[1], ф[2]);
    проверить('склонение: ' + п[0] + ' ' + ф[п[1]], факт === ф[п[1]], факт);
  }
}

// --- Номера Telegram ---
const всё = [нет, до, до3, записан, идёт, доигрыш, после, несостоялся].map(всеТексты).join('\n');
проверить('номеров Telegram в выводе модели нет', всё.indexOf(String(НОМЕР_ТЕЛЕГРАМ)) === -1 && всё.indexOf(String(НОМЕР_ТЕЛЕГРАМ + 1)) === -1);

// --- Страховка от пустой проверки ---
проверить('проверка видела состояния и строки (не ноль)', идёт.строки.length > 0 && после.строки.length > 0 && всего > 20);

console.log('\nИтого: ' + (всего - упало) + ' из ' + всего + ' зелёных');
process.exit(упало === 0 ? 0 : 1);
