const fs = require('fs');
const path = require('path');

// Разрешённые файлы в корне проекта
const разрешённыеФайлы = new Set([
  'CLAUDE.md',
  'README.md',
  'ЗАДАЧИ.md',
  'эталон-вида.md',
  'ЗАПУСК-БЕЗ-ВОПРОСОВ.cmd',
  'index.html',
  'шашки.html',
  'шахматы.html',
  'нарды.html',
  'style.css',
  'style-шашки.css',
  'style-шахматы.css',
  'style-нарды.css',
  '.gitignore',
  '.gitattributes',
]);

// Разрешённые папки в корне проекта
const разрешённыеПапки = new Set([
  'js',
  'server',
  'bot',
  'tests',
  'img',
  'эталон',
  'штаб',
  'шрифты',
  'снимки',
  '.git',
  '.claude',
  'node_modules',
  '.playwright-mcp',
]);

function проверитьКорень(сломать = false) {
  const кореньПроекта = path.join(__dirname, '..');

  // Если флаг --сломать, используем виртуальный список с лишним элементом
  let элементы;
  if (сломать) {
    элементы = ['CLAUDE.md', '.git', 'js', 'tests', 'ЛИШНИЙ_ФАЙЛ.txt', 'папка-лишняя'];
  } else {
    элементы = fs.readdirSync(кореньПроекта);
  }

  const провалы = [];
  let проверок = 0;

  for (const элемент of элементы) {
    проверок++;

    // Пропускаем файлы, начинающиеся с точки (служебные файлы)
    if (элемент.startsWith('.')) {
      continue;
    }

    let этоПапка = false;
    if (!сломать) {
      const полнойПуть = path.join(кореньПроекта, элемент);
      этоПапка = fs.statSync(полнойПуть).isDirectory();
    } else {
      // Для сломанного режима определяем тип по наличию точки (файлы с расширением, папки без)
      этоПапка = !элемент.includes('.');
    }

    if (этоПапка) {
      // Проверяем папку
      if (!разрешённыеПапки.has(элемент)) {
        провалы.push(`  папка: ${элемент}`);
      }
    } else {
      // Проверяем файл
      if (!разрешённыеФайлы.has(элемент)) {
        провалы.push(`  файл: ${элемент}`);
      }
    }
  }

  // Вывод результатов
  console.log(`Итого проверок: ${проверок}, провалов: ${провалы.length}`);

  if (провалы.length > 0) {
    console.log('\nЛишнее в корне проекта:');
    console.log(провалы.join('\n'));
    console.log('\nПодсказка: снимки — в tests/снимки/, черновики — в scratchpad');
    process.exit(1);
  }
}

// Проверяем флаг --сломать
const флаг = process.argv[2];
const сломать = флаг === '--сломать';

проверитьКорень(сломать);
