const fs = require('fs');
const path = require('path');

// Разрешённые файлы в корне проекта с точным именем (не по расширению)
const разрешённыеФайлы = new Set([
  'CLAUDE.md',
  'README.md',
  'ЗАДАЧИ.md',
  'эталон-вида.md',
  'ЗАПУСК-БЕЗ-ВОПРОСОВ.cmd',
  '.gitignore',
  '.gitattributes',
  // Для поисковиков (план привлечения, раздел 7): только эти два имени, не «любой txt/xml»
  'robots.txt',
  'sitemap.xml',
]);

// Правило владельца (09.10): в корне только страницы (html). Новую игру (катан.html)
// поимённо вписывать не нужно. Оформление и js игры живут в игры/<игра>/, общие — в общее/.
const разрешённыеРасширения = new Set(['.html']);

// Единственный css в корне: временная копия, убрать вместе с переадресациями
const разрешённыйCss = new Set(['style-свернуть.css']);

// Папки, которых в корне быть не должно (переехали в игры/ и общее/)
const запрещённыеПапки = new Set(['js', 'шрифты']);

// Разрешённые папки в корне проекта
const разрешённыеПапки = new Set([
  'игры',
  'общее',
  'server',
  'bot',
  'tests',
  'img',
  // Публичные страницы /rules/<игра>/ по ТЗ привлечения игроков.
  'rules',
  'эталон',
  'штаб',
  'снимки',
  '.git',
  '.claude',
  'node_modules',
  '.playwright-mcp',
]);

function проверитьКорень(кореньПроекта = null) {
  if (!кореньПроекта) {
    кореньПроекта = path.join(__dirname, '..');
  }

  const элементы = fs.readdirSync(кореньПроекта);

  const провалы = [];
  let проверок = 0;

  for (const элемент of элементы) {
    проверок++;

    // Пропускаем файлы, начинающиеся с точки (служебные файлы)
    if (элемент.startsWith('.')) {
      continue;
    }

    const полнойПуть = path.join(кореньПроекта, элемент);
    const этоПапка = fs.statSync(полнойПуть).isDirectory();

    if (этоПапка) {
      // Проверяем папку
      if (запрещённыеПапки.has(элемент)) {
        провалы.push(`  папка: ${элемент} (файл игры — в игры/<игра>/, общий — в общее/)`);
      } else if (!разрешённыеПапки.has(элемент)) {
        провалы.push(`  папка: ${элемент}`);
      }
    } else {
      // Проверяем файл: разрешён по точному имени ИЛИ по расширению (html)
      const расширение = path.extname(элемент).toLowerCase();
      const законенПоРасширению = разрешённыеРасширения.has(расширение) || разрешённыйCss.has(элемент);
      if (!разрешённыеФайлы.has(элемент) && !законенПоРасширению) {
        const совет = (расширение === '.js' || расширение === '.css') ? ' (файл игры — в игры/<игра>/, общий — в общее/)' : '';
        провалы.push(`  файл: ${элемент}${совет}`);
      }
    }
  }

  // Вывод результатов
  console.log(`Итого проверок: ${проверок}, провалов: ${провалы.length}`);

  if (провалы.length > 0) {
    console.log('\nЛишнее в корне проекта:');
    console.log(провалы.join('\n'));
    console.log('\nПодсказка: снимки — в tests/снимки/, черновики — в scratchpad; css и js игры — в игры/<игра>/, общие — в общее/js и общее/css');
    process.exit(1);
  }
}

// Проверяем доводы: --папка=/путь для проверки копии
let папкаДляПроверки = null;
for (const довод of process.argv.slice(2)) {
  if (довод.startsWith('--папка=')) {
    папкаДляПроверки = довод.substring('--папка='.length);
  }
}

проверитьКорень(папкаДляПроверки);
