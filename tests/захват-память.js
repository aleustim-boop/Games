  с5.п.добавитьРекорд(рекорд(1, 30, 777));
  с5.п.положить('эффекты', false);
  await пауза();
  надо(облако5.записей === 2, 'облако получило ровно две записи: рекорды и эффекты (получило ' + облако5.записей + ')');
  надо(облако5.отказы.length === 0, 'облако не отказывало ни одному ключу (имена годятся)');
  надо(JSON.parse(облако5.ящик['zahvat-records']).length === 1, 'рекорд лёг в облако');
  // новый телефон, дома пусто, в облаке есть всё
  const новыйТелефон = страница(сделатьПамять(false), сделатьОблако({ ящик: облако5.ящик }));
  надо(новыйТелефон.п.рекорды().length === 0, 'на новом телефоне до ответа облака рекордов дома нет');
  let ответ = null;
  новыйТелефон.п.подтянуть(function (изменилось) { ответ = изменилось; });
  await пауза();
  надо(ответ === true, 'подтянуть сообщил, что что-то изменилось');
  надо(новыйТелефон.п.рекорды().length === 1 && новыйТелефон.п.рекорды()[0].когда === 777, 'рекорд из облака приехал на новый телефон');
  надо(новыйТелефон.п.взять('эффекты', 'нет') === false, 'настройка из облака приехала на новый телефон');
  // слияние: дома одна строка, в облаке другая — остаются обе
  const облако6 = сделатьОблако({ ящик: { 'zahvat-records': JSON.stringify([рекорд(2, 9, 111)]) } });
  const с6 = страница(сделатьПамять(false), облако6);
  с6.п.добавитьРекорд(рекорд(1, 20, 222));
  с6.п.подтянуть(function () {});
  await пауза();
  надо(с6.п.рекорды().length === 2, 'слияние: не потерялась ни местная, ни облачная строка');
  надо(JSON.parse(облако6.ящик['zahvat-records']).length === 2, 'новая запись не затёрла чужую строку в облаке');
