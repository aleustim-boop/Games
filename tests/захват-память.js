function сломатьИПроверить() {
  const где = process.argv.indexOf('--сломать');
  const своя = process.argv[где + 1] && !process.argv[где + 1].startsWith('--') ? process.argv[где + 1] : null;
  const папка = своя ? path.resolve(своя) : fs.mkdtempSync(path.join(os.tmpdir(), 'захват-память-лом-'));
  const отКорня = path.relative(path.join(__dirname, '..'), папка);
  if (!отКорня.startsWith('..') && !path.isAbsolute(отКорня)) {
    console.log('Папка порчи внутри проекта — копии кладутся только вне его: ' + папка);
    process.exit(3);
  }
  fs.mkdirSync(папка, { recursive: true });
  let покраснело = 0, код = 0;
  ПОРЧИ.forEach(function (порча, номер) {
    const мест = исходник.split(порча.было).length - 1;
    if (мест !== 1) {
      console.log('Порча ' + (номер + 1) + ' («' + порча.имя + '»): место найдено ' + мест + ' раз вместо одного — код 3');
      код = Math.max(код, 3);
      return;
    }
    const копия = path.join(папка, 'порча-' + (номер + 1) + '-захват-память.js');
    fs.writeFileSync(копия, исходник.replace(порча.было, function () { return порча.стало; }), 'utf8');
    const запуск = spawnSync(process.execPath, [__filename, '--файл', копия], { encoding: 'utf8' });
    const красных = запуск.stdout.match(/^ПРОВАЛ: .*/gm) || [];
    const покраснела = запуск.status === 1 && красных.length > 0;
    if (покраснела) покраснело++; else код = Math.max(код, 2);
    console.log('Порча ' + (номер + 1) + ' («' + порча.имя + '»): код выхода ' + запуск.status + ', красных пунктов ' + красных.length
      + (покраснела ? '' : ' — НЕ ПОКРАСНЕЛА'));
    красных.slice(0, 3).forEach(function (с) { console.log('   ' + с); });
  });
  console.log('Папка копий: ' + папка);
  console.log('Поломок: ' + ПОРЧИ.length + ', покраснело: ' + покраснело);
  console.log('Итого проверок: ' + ПОРЧИ.length + ', провалов: ' + (ПОРЧИ.length - покраснело));
  process.exit(код);
}

if (process.argv.indexOf('--сломать') !== -1) сломатьИПроверить();
else главная().then(function () {
  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
}, function (ошибка) {
  console.log('ПРОВАЛ: проверка упала: ' + ошибка.message);
  console.log('Итого проверок: ' + (проверок + 1) + ', провалов: ' + (провалов + 1));
  process.exit(1);
});
