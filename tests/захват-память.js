  const молчит = страница(сделатьПамять(false), сделатьОблако({ молчит: true }));
  молчит.п.добавитьРекорд(рекорд(1, 1, 1));
  надо(молчит.п.рекорды().length === 1, 'облако молчит — рекорд всё равно лёг в память телефона');
  const отказ = страница(сделатьПамять(false), сделатьОблако({ отказывает: true }));
  отказ.п.добавитьРекорд(рекорд(1, 1, 1));
  let ответилоОтказавшее = false;
  отказ.п.подтянуть(function () { ответилоОтказавшее = true; });
  await пауза();
  надо(отказ.п.рекорды().length === 1 && ответилоОтказавшее, 'облако отказывает — рекорд цел, подтягивание завершилось');
  // без облака
  let безОблака = null;
  страница(сделатьПамять(false), null).п.подтянуть(function (и) { безОблака = и; });
  надо(безОблака === false, 'без облака подтянуть отвечает «ничего не изменилось»');

