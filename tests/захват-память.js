const индексДовода = process.argv.indexOf('--файл');
const ФАЙЛ = индексДовода !== -1 && process.argv[индексДовода + 1]
  ? path.resolve(process.argv[индексДовода + 1])
  : path.join(__dirname, '..', 'игры', 'захват', 'захват-память.js');
const исходник = fs.readFileSync(ФАЙЛ, 'utf8');

let проверок = 0, провалов = 0;
function надо(условие, что) {
  проверок++;
  if (!условие) { провалов++; console.log('ПРОВАЛ: ' + что); }
}

/** Поднять страницу с этим файлом на данной памяти и облаке («перезапуск» = поднять заново на той же памяти). */
function страница(память, облако) {
  const с = поднять(исходник, { память: память, облако: облако || null, имяФайла: ФАЙЛ });
  const модуль = с.окно.ЗахватПамять;
  надо(!!модуль && typeof модуль.открыть === 'function', 'файл кладёт window.ЗахватПамять с функцией «открыть»');
  if (!модуль) throw new Error('нет ЗахватПамять — дальше проверять нечего');
  return { модуль: модуль, память: с.память, облако: облако,
    п: модуль.открыть({ память: память, облако: облако || null }) };
}

const пауза = function () { return new Promise(function (ок) { setTimeout(ок, 20); }); };
const рекорд = function (место, очки, когда, ещё) {
  return Object.assign({ когда: когда, режим: 'боты', мест: 4, место: место, очки: очки, раундов: 9 }, ещё || {});
};

