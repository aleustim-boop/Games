  // «Пригласить друзей» (зов в приложение, комнату не заводит). Три шага
  // создания комнаты теперь открывает «Создать игру» на экране «Играть
  // онлайн»: лобби → «лобби-играть-онлайн» → экран-открытые-столы →
  // «открытые-столы-создать» → те же три шага, что и раньше.
  await нажать(страница, страница.locator('#лобби-играть-онлайн'));
  await дождаться(страница, 'экран-открытые-столы');
