  await дождаться(страница, 'экран-путь-игроки');
  await нажать(страница, страница.locator('#путь-числа .числа__число', { hasText: /^\s*3\s*$/ }));
  await нажать(страница, страница.locator('.экран.экран--виден [data-путь="далее"]'));
  await дождаться(страница, 'экран-путь-настройки');
  await нажать(страница, страница.locator('#путь-начать'));
