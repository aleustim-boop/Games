const журнал = [];
function поддельныйTelegram(метод, тело) {
  журнал.push({ метод: метод, тело: тело });
  if (метод === 'getMe') return { ok: true, result: { id: 777, is_bot: true, username: ИМЯ_БОТА } };
  if (метод === 'sendMessage') return { ok: true, result: { message_id: журнал.length } };
  return { ok: false, error_code: 400, description: 'Bad Request' };
}
function писемКому(номер) {
  return журнал.filter((з) => з.метод === 'sendMessage' && Number(з.тело.chat_id) === номер).length;
}

function подписатьInitData(кто) {
  const поля = new URLSearchParams();
  поля.set('user', JSON.stringify(кто));
  поля.set('auth_date', String(Math.floor(Date.now() / 1000)));
  const строки = [];
  for (const пара of поля) строки.push(пара[0] + '=' + пара[1]);
  строки.sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(ТОКЕН).digest();
  поля.set('hash', crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex'));
  return поля.toString();
}

function постучать(адрес) {
  return new Promise(function (готово) {
    const з = http.get(адрес, function (о) { о.resume(); готово(о.statusCode); });
    з.on('error', () => готово(0));
    з.setTimeout(1500, function () { з.destroy(); готово(0); });
  });
}
