'use strict';

/* =====================================================================
   Автопрогон партий компанией: «человек против ботов» много раз подряд.

   Зачем это нужно. Руками в браузере можно сыграть пять-десять партий,
   а редкие поломки (партия зависла, сервер отказал на то, что игра сама
   предложила, дурак не назван) вылезают на сотой. Поэтому здесь та же
   игра, но без картинки: скрипт садится за стол вместо человека и жмёт
   те же кнопки запросами к серверу комнат.

   Как запускать (сервер комнат должен быть уже поднят):

       node tests/автопрогон-компанией.js
       node tests/автопрогон-компанией.js 8790 30

   Первое число — порт сервера комнат (по умолчанию 8790),
   второе — сколько партий сыграть в каждой раскладке стола.

   Что считается поломкой:
     • партия не кончилась за отведённое число ходов — «зависла»;
     • сервер отказал на действие, которое сам же разрешил в состоянии;
     • партия кончилась, а дурак не назван;
     • ответ сервера не пришёл или пришёл с ошибкой.

   Скрипт ничего не чинит и ничего не меняет в игре: он только играет
   и считает. Библиотек не требует — только сам Node.
   ===================================================================== */

const http = require('http');

const ПОРТ = Number(process.argv[2]) || 8790;
const ПАРТИЙ_НА_РАСКЛАДКУ = Number(process.argv[3]) || 20;
const ХОЗЯИН = '127.0.0.1';

/* Больше этого числа действий в одной партии — считаем, что она зависла.
   Живая партия вшестером укладывается сотни в полторы. */
const ПОТОЛОК_ДЕЙСТВИЙ = 900;

/* Сколько ждём, пока сходят боты, прежде чем решить, что стол замер. */
const ЖДЁМ_БОТОВ_МС = 12000;

/* Раскладки стола, которые проверяем. */
const РАСКЛАДКИ = [
  { имя: 'трое, обычный',            мест: 3, переводной: false, парами: false },
  { имя: 'четверо, обычный',         мест: 4, переводной: false, парами: false },
  { имя: 'пятеро, обычный',          мест: 5, переводной: false, парами: false },
  { имя: 'шестеро, обычный',         мест: 6, переводной: false, парами: false },
  { имя: 'четверо, переводной',      мест: 4, переводной: true,  парами: false },
  { имя: 'шестеро, переводной',      мест: 6, переводной: true,  парами: false },
  { имя: 'четверо, парами',          мест: 4, переводной: false, парами: true  },
  { имя: 'четверо, парами+перевод',  мест: 4, переводной: true,  парами: true  }
];

/* ------------------------------------------------------------------ */
/* Разговор с сервером                                                 */
/* ------------------------------------------------------------------ */

function спросить(путь, тело) {
  return new Promise((готово, беда) => {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, (ответ) => {
      let текст = '';
      ответ.setEncoding('utf8');
      ответ.on('data', (кусок) => { текст += кусок; });
      ответ.on('end', () => {
        let разобрано = null;
        try { разобрано = JSON.parse(текст); } catch (сбой) { разобрано = { сырое: текст }; }
        готово({ код: ответ.statusCode, тело: разобрано });
      });
    });
    запрос.setTimeout(40000, () => { запрос.destroy(new Error('сервер молчит дольше 40 секунд')); });
    запрос.on('error', беда);
    запрос.end(данные);
  });
}

const пауза = (мс) => new Promise((r) => setTimeout(r, мс));

/* ------------------------------------------------------------------ */
/* Простые решения за игрока — как у неспешного новичка                */
/* ------------------------------------------------------------------ */

/** Старше ли карта «чем» карту «что» по правилам подкидного. */
function бьёт(чем, что, козырь) {
  if (чем.масть === что.масть) return чем.вес > что.вес;
  return чем.масть === козырь && что.масть !== козырь;
}

/** Первая неотбитая пара на столе (её номер) — по ней и отбиваются. */
function номерНеотбитой(стол) {
  for (let i = 0; i < стол.length; i++) {
    if (!стол[i].защита) return i;
  }
  return -1;
}

/**
 * Что делать игроку прямо сейчас. Возвращает намерение для /ход
 * или null, если ходить не наша очередь.
 *
 * Играем как спокойный новичок: отбиваемся самой дешёвой подходящей
 * картой, подкидываем что лежит, переводим когда игра сама разрешила.
 */
function решить(вид) {
  const рука = вид.мояРука || [];
  const стол = вид.стол || [];
  const козырь = вид.козырь;

  // Я отбиваюсь
  if (вид.яОтбиваюсь && !вид.берут) {
    const номер = номерНеотбитой(стол);
    if (номер >= 0) {
      const атакующая = стол[номер].атака;
      // перевести пробуем первым делом — иначе переводной так и не проверится
      if (вид.могуПеревести) {
        const такаяЖе = рука.findIndex((к) => стол.every((п) => !п.защита) &&
          стол.some((п) => п.атака && п.атака.вес === к.вес));
        if (такаяЖе >= 0) return { действие: 'перевести', карта: такаяЖе };
      }
      const годные = рука.map((к, i) => ({ к, i }))
        .filter((п) => атакующая && бьёт(п.к, атакующая, козырь))
        .sort((а, б) => (а.к.масть === козырь ? 1 : 0) - (б.к.масть === козырь ? 1 : 0) || а.к.вес - б.к.вес);
      if (годные.length) return { действие: 'отбить', пара: номер, карта: годные[0].i };
      return { действие: 'беру' };
    }
    return null;
  }

  /* Я хожу или подкидываю.
     Смотрим именно «яХожу»: поле «могуПодкинуть» означает лишь «есть чем»,
     а очередь может быть у соседа — на такой ход сервер честно отказывает. */
  if (вид.яХожу) {
    if (!рука.length) return null;
    if (!стол.length) {
      // ходим самой слабой некозырной картой
      const порядок = рука.map((к, i) => ({ к, i }))
        .sort((а, б) => (а.к.масть === козырь ? 1 : 0) - (б.к.масть === козырь ? 1 : 0) || а.к.вес - б.к.вес);
      return { действие: 'ходить', карта: порядок[0].i };
    }
    // подкидываем то, что уже лежит по достоинству
    const веса = new Set();
    стол.forEach((п) => {
      if (п.атака) веса.add(п.атака.вес);
      if (п.защита) веса.add(п.защита.вес);
    });
    const годная = рука.findIndex((к) => веса.has(к.вес) && к.масть !== козырь);
    if (годная >= 0) return { действие: 'ходить', карта: годная };
    return { действие: 'бито' };
  }

  return null;
}

