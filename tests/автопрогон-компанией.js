async function сыгратьПартию(раскладка, номерПартии) {
  const беды = [];
  const создано = await спросить('/создать', {
    мест: раскладка.мест, переводной: раскладка.переводной, парами: раскладка.парами, имя: 'Проверка'
  });
  if (создано.код !== 200 || !создано.тело.код) {
    return { беды: [{ что: 'комната не создалась', ответ: создано }], итог: null };
  }
  const код = создано.тело.код;
  const пропуск = создано.тело.пропуск;

  // сажаем ботов на все свободные места
  for (let i = 0; i < раскладка.мест - 1; i++) {
    const о = await спросить('/ход', { код, пропуск, действие: 'бот' });
    if (о.код !== 200 || (о.тело && о.тело.принято === false)) {
      беды.push({ что: 'бот не сел', номер: i + 1, ответ: о.тело });
    }
  }

  const начали = await спросить('/ход', { код, пропуск, действие: 'начать' });
  if (начали.код !== 200 || (начали.тело && начали.тело.принято === false)) {
    беды.push({ что: 'игра не началась', ответ: начали.тело });
    return { беды, итог: null };
  }

  let итог = null;
  let действий = 0;
  let последнееШевеление = Date.now();
  let прошлыйСлепок = '';

  while (действий < ПОТОЛОК_ДЕЙСТВИЙ) {
    const с = await спросить('/состояние', { код, пропуск });
    if (с.код !== 200) {
      беды.push({ что: 'сервер потерял комнату посреди партии', код: с.код, ответ: с.тело, действий });
      break;
    }
    const вид = с.тело && с.тело.состояние ? с.тело.состояние : с.тело;
    if (вид.завершена) {
      итог = {
        итог: вид.итог,
        проигравшие: (вид.застолом || []).filter((м) => м.проиграл).map((м) => м.имя)
      };
      break;
    }

    const решение = решить(вид);
    const намерение = решение.намерение;
    if (решение.жалоба) {
      беды.push({ что: 'состояние противоречит само себе: ' + решение.жалоба, вид: краткоВид(вид), действий });
    }
    /* По чему решаем, что стол шевелится. Фазу и «могу подкинуть» берём
       сюда нарочно: когда боты по кругу молча пасуют, ни стол, ни наши
       карты не меняются, и без этих двух полей стол выглядел бы замершим,
       хотя партия идёт своим ходом. */
    const слепок = JSON.stringify([вид.стол, вид.мояРука.length, вид.яХожу,
      вид.яОтбиваюсь, вид.берут, вид.фаза, вид.могуПодкинуть]);
    if (слепок !== прошлыйСлепок) { прошлыйСлепок = слепок; последнееШевеление = Date.now(); }

    if (!намерение) {
      /* Стол долго не шевелится, а нам, если верить состоянию, ходить
         нечего. Пробуем сказать «Бито»: если сервер это ПРИМЕТ, значит
         ждали всё-таки нас, а состояние показывало обратное — и это
         поломка, а не мелочь. Раньше здесь стояло «значит, ждали нас,
         и это не поломка», и такой ответ прятал ровно ту беду, которую
         этот прогон и должен ловить: игрок не видит, что ход за ним. */
      if (Date.now() - последнееШевеление > 4000) {
        /* Перед пробой перечитываем состояние вплотную. Это не лишний
           запрос, а защита от гонки, на которую проверка уже попалась:
           боты ходят с паузой в 0,7 секунды, и пока они молча пасуют
           по кругу, наш слепок не меняется — стол тот же, рука та же.
           Слово доходит до нас как раз к четвёртой секунде, и старое
           состояние «ход не ваш» успевает устареть за миг до пробы.
           Тогда принятое «Бито» — не поломка игры, а наша несвежая
           бумажка. Свежее чтение оставляет между вопросом и ходом
           миллисекунды вместо секунд. */
        const свежее = await спросить('/состояние', { код, пропуск });
        const свежийВид = свежее.тело && свежее.тело.состояние ? свежее.тело.состояние : свежее.тело;
        if (свежее.код === 200 && свежийВид && !свежийВид.завершена) {
          const свежееРешение = решить(свежийВид);
          if (свежееРешение.намерение) {
            // Ход всё-таки появился — играем дальше, это не поломка.
            последнееШевеление = Date.now();
            continue;
          }
          const проба = await спросить('/ход', { код, пропуск, действие: 'бито' });
          if (проба.код === 200 && проба.тело && проба.тело.принято) {
            беды.push({
              что: 'сервер принял от нас «Бито», хотя в состоянии — только что прочитанном — не было ' +
                   'ни «ваш ход», ни возможности подкинуть: живой игрок в этот миг не понял бы, что ждут его',
              вид: краткоВид(свежийВид), действий
            });
            последнееШевеление = Date.now();
            действий++;
            await пауза(200);
            continue;
          }
        }
      }
      if (Date.now() - последнееШевеление > ЖДЁМ_БОТОВ_МС) {
        беды.push({ что: 'партия замерла: ходить некому', вид: краткоВид(вид), действий });
        break;
      }
      await пауза(250);
      continue;
    }

    const о = await спросить('/ход', Object.assign({ код, пропуск }, намерение));
    действий++;
    if (о.код !== 200) {
      беды.push({ что: 'сервер ответил ошибкой на ход', код: о.код, намерение, ответ: о.тело });
      break;
    }
    if (о.тело && о.тело.принято === false) {
      /* ЛЮБОЙ отказ — поломка, и разбирать его по словам причины мы больше
         не будем. Мы посылаем только то, что состояние показало возможным,
         значит отказ означает одно: игра обещала игроку не то, что делает.

         Раньше здесь стояла проверка причины по словам («подкид», «меньше
         карт»), и такие отказы прощались как «наша недоработка». Из-за неё
         прогон однажды позеленел по случайности: сервер сменил текст отказа
         на «Вы сказали "Пас" — подкидывать до конца подхода больше нельзя»,
         слово «подкид» в нём нашлось — и 898 настоящих отказов молча ушли
         в «прощено». Проверка, которая читает слова вместо сути, зелена
         ровно до следующей правки текста. */
      беды.push({
        что: 'сервер отказал на ход, который сам же показал возможным',
        намерение, причина: о.тело.причина, вид: краткоВид(вид)
      });
      /* Чтобы партия всё-таки доигралась и было видно, что сломалось
         дальше, закрываем подход и идём вперёд. Поломка уже записана. */
      await спросить('/ход', { код, пропуск, действие: 'бито' });
      await пауза(200);
    }
    последнееШевеление = Date.now();
  }

  if (!итог && !беды.length) {
    беды.push({ что: 'партия не кончилась за ' + ПОТОЛОК_ДЕЙСТВИЙ + ' действий' });
  }
  if (итог && !итог.итог) {
    беды.push({ что: 'партия кончилась, а итога нет', итог });
  }
  if (итог && итог.итог && итог.итог !== 'ничья' && !итог.проигравшие.length) {
    беды.push({ что: 'партия кончилась, а дурак не назван', итог });
  }
  if (итог && раскладка.парами && итог.проигравшие.length === 1) {
    беды.push({ что: 'игра парами, а проиграл один, не пара', итог });
  }

  await спросить('/выйти', { код, пропуск });
  return { беды, итог, действий, код };
}

function краткоВид(вид) {
  return {
    фаза: вид.фаза, яХожу: вид.яХожу, яОтбиваюсь: вид.яОтбиваюсь,
    могуПодкинуть: вид.могуПодкинуть, берут: вид.берут,
    вКолоде: вид.вКолоде, картВРуке: (вид.мояРука || []).length,
    паруНаСтоле: (вид.стол || []).length,
    застолом: (вид.застолом || []).map((м) => м.имя + ':' + м.карт +
      (м.ходит ? ' (ходит)' : '') + (м.отбивается ? ' (отбивается)' : '') + (м.выбыл ? ' (вышел)' : ''))
  };
}

