/**
 * Убеждаемся, что решения принимаются по полям состояния, а не мимо них.
 *
 * Зачем это здесь. Главную беду этого прогона — «шлём ход, который сервер
 * сам же показал невозможным» — на живом сервере поймать трудно: нужное
 * положение выпадает редко, и десяток партий может пройти впустую. Поэтому
 * тот же вопрос задаём напрямую и без сервера: подсовываем решателю
 * несколько придуманных состояний и смотрим, что он собирается послать.
 *
 * Проверка идёт перед партиями. Не прошла — прогон дальше не идёт: играть
 * тем, кто не смотрит на состояние, бессмысленно, зелёный итог такой игры
 * ничего не значит.
 */
function проверитьСамогоСебя() {
  const беды = [];
  const к = (имя, масть, вес) => ({ имя, масть, вес });
  // Стол: 6♣ побита 7♣. Достоинства на столе — шестёрка и семёрка.
  const общее = {
    козырь: '♠', яОтбиваюсь: false, берут: false, могуПеревести: false,
    стол: [{ атака: к('6', '♣', 0), защита: к('7', '♣', 1) }],
    застолом: [{ имя: 'я', этоЯ: true, карт: 1, ходит: true },
               { имя: 'сосед', карт: 5, отбивается: true }],
    мояРука: [к('6', '♦', 0)]      // шестёрка есть — по столу она годится
  };
  const состояние = (добавка) => Object.assign({}, общее, добавка);
  const что = (решение) => (решение.намерение ? решение.намерение.действие : 'ничего');

  // 1. Поле говорит «класть нельзя» — карту не шлём, а закрываем подход.
  if (что(решить(состояние({ яХожу: true, могуПодкинуть: false }))) !== 'бито') {
    беды.push('прогон шлёт карту, хотя в состоянии стоит «могуПодкинуть: false» — ' +
      'он не смотрит на это поле, и любой зелёный итог ничего не значит');
  }
  // 2. Поле говорит «можно» — кладём карту.
  if (что(решить(состояние({ яХожу: true, могуПодкинуть: true }))) !== 'ходить') {
    беды.push('прогон не кладёт карту, хотя состояние это разрешает — он не сыграет партию до конца');
  }
  // 3. Ход не наш — не шлём ничего, что бы поле ни обещало.
  if (что(решить(состояние({ яХожу: false, могуПодкинуть: true }))) !== 'ничего') {
    беды.push('прогон ходит не в свою очередь: «яХожу» стоит false, а он всё равно шлёт ход');
  }
  // 4. Потолок в шесть карт: больше не кладут, даже когда поле разрешает.
  const шестьПар = [];
  for (let i = 0; i < 6; i++) шестьПар.push({ атака: к('6', '♣', 0), защита: к('7', '♣', 1) });
  if (что(решить(состояние({ яХожу: true, могуПодкинуть: true, стол: шестьПар }))) !== 'бито') {
    беды.push('прогон подкидывает седьмую карту за подход — потолка в шесть карт он не знает');
  }
  // 5. У отбивающегося карт меньше, чем неотбитых, — крыть ему нечем, не подкидываем.
  const тесно = состояние({
    яХожу: true, могуПодкинуть: true,
    стол: [{ атака: к('6', '♣', 0), защита: null }],
    застолом: [{ имя: 'я', этоЯ: true, карт: 1, ходит: true },
               { имя: 'сосед', карт: 1, отбивается: true }]
  });
  if (что(решить(тесно)) !== 'бито') {
    беды.push('прогон подкидывает больше, чем у отбивающегося карт на руках');
  }
  // 6. Карт на руках нет, но слово наше — подход закрываем мы, а не молчим.
  if (что(решить(состояние({ яХожу: true, могуПодкинуть: false, мояРука: [] }))) !== 'бито') {
    беды.push('прогон молчит с пустой рукой, хотя закрыть подход должен он — стол замрёт на пустом месте');
  }
  return беды;
}

