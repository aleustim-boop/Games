/* =====================================================================
   Автопрогон партий компанией: «человек против ботов» много раз подряд.

   Зачем это нужно. Руками в браузере можно сыграть пять-десять партий,
   а редкие поломки (партия зависла, сервер отказал на то, что игра сама
   предложила, дурак не назван) вылезают на сотой. Поэтому здесь та же
   игра, но без картинки: скрипт садится за стол вместо человека и жмёт
   те же кнопки запросами к серверу комнат.

   Как запускать (сервер комнат должен быть уже поднят):

       node tests/автопрогон-компанией.js
       node tests/автопрогон-компанией.js 8790 30

   Первое число — порт сервера комнат (по умолчанию 8790),
   второе — сколько партий сыграть в каждой раскладке стола.

   Что считается поломкой:
     • партия не кончилась за отведённое число ходов — «зависла»;
     • сервер отказал на ход, который сам же показал возможным;
     • состояние противоречит само себе (например, «ваш ход» при пустом
       столе, а положить карту игрок не вправе);
     • сервер принял «Бито», хотя в состоянии не было ни «ваш ход»,
       ни возможности подкинуть;
     • партия кончилась, а дурак не назван;
     • ответ сервера не пришёл или пришёл с ошибкой.

   КАК ЭТОТ ПРОГОН РЕШАЕТ, ЧТО ДЕЛАТЬ. Только по полям состояния — по тем
   же самым, по которым игра рисует кнопки живому игроку: «яХожу»,
   «яОтбиваюсь», «могуПодкинуть», «могуПеревести», карты на столе и число
   карт у соперников. Ни одно решение не принимается по ТЕКСТУ сообщений
   сервера, и это не вкусовщина: тексты меняются, а проверка, которая
   их читает, зеленеет и краснеет от правки слов, а не от правки игры.
   Однажды так и вышло — прогон прощал отказы, в причине которых
   встречалось слово «подкид», и молча простил 898 настоящих отказов,
   когда сервер сменил формулировку.

   Скрипт ничего не чинит и ничего не меняет в игре: он только играет
   и считает. Библиотек не требует — только сам Node.
   ===================================================================== */

