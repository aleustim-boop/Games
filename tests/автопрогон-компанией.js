/** Старше ли карта «чем» карту «что» по правилам подкидного. */
function бьёт(чем, что, козырь) {
  if (чем.масть === что.масть) return чем.вес > что.вес;
  return чем.масть === козырь && что.масть !== козырь;
}

/** Первая неотбитая пара на столе (её номер) — по ней и отбиваются. */
function номерНеотбитой(стол) {
  for (let i = 0; i < стол.length; i++) {
    if (!стол[i].защита) return i;
  }
  return -1;
}

/** Сколько карт на столе ещё не отбито. */
function сколькоНеотбитых(стол) {
  let счёт = 0;
  for (const пара of стол) if (!пара.защита) счёт++;
  return счёт;
}

/**
 * Сколько карт в руке у того, кто сейчас отбивается. Нужно для правила
 * «подкидывать можно не больше, чем у него карт»: иначе крыть ему нечем.
 * Число видно каждому за столом — сервер шлёт его в списке мест.
 */
function картУОтбивающегося(вид) {
  for (const место of вид.застолом || []) {
    if (место.отбивается) return место.карт;
  }
  return null;
}

/* Больше шести карт за один подход не кладут. */
const МАКС_КАРТ_В_ПОДХОДЕ = 6;

/**
 * Что делать игроку прямо сейчас.
 * Возвращает { намерение, жалоба }: намерение — что послать серверу
 * (или null, если ходить не наша очередь), жалоба — текст поломки,
 * если состояние противоречит само себе.
 *
 * Играем как спокойный новичок: отбиваемся самой дешёвой подходящей
 * картой, подкидываем что лежит, переводим когда игра сама разрешила.
 *
 * ГЛАВНОЕ ПРАВИЛО ЭТОГО ПРОГОНА: не посылать серверу того, что он сам
 * же показал невозможным. Живой игрок так и играет — он жмёт только то,
 * что ему предложили. Поэтому любой отказ сервера здесь считается
 * поломкой, а не «нашей недоработкой»: если мы послали ход, значит
 * состояние обещало, что он пройдёт.
 */
function решить(вид) {
  const рука = вид.мояРука || [];
  const стол = вид.стол || [];
  const козырь = вид.козырь;

  // Я отбиваюсь
  if (вид.яОтбиваюсь && !вид.берут) {
    const номер = номерНеотбитой(стол);
    if (номер >= 0) {
      const атакующая = стол[номер].атака;
      // перевести пробуем первым делом — иначе переводной так и не проверится
      if (вид.могуПеревести) {
        const такаяЖе = рука.findIndex((к) => стол.every((п) => !п.защита) &&
          стол.some((п) => п.атака && п.атака.вес === к.вес));
        if (такаяЖе >= 0) return { намерение: { действие: 'перевести', карта: такаяЖе }, жалоба: null };
      }
      const годные = рука.map((к, i) => ({ к, i }))
        .filter((п) => атакующая && бьёт(п.к, атакующая, козырь))
        .sort((а, б) => (а.к.масть === козырь ? 1 : 0) - (б.к.масть === козырь ? 1 : 0) || а.к.вес - б.к.вес);
      if (годные.length) return { намерение: { действие: 'отбить', пара: номер, карта: годные[0].i }, жалоба: null };
      return { намерение: { действие: 'беру' }, жалоба: null };
    }
    return { намерение: null, жалоба: null };
  }

  /* Я хожу или подкидываю.
     Спрашиваем два разных поля, и путать их нельзя:
       «яХожу»        — сейчас ждут моего слова;
       «могуПодкинуть»— я вправе ПОЛОЖИТЬ карту прямо сейчас.
     Это не одно и то же. Спасовавшему слово возвращают в конце подхода,
     чтобы он сказал «Бито», но класть карту он больше не вправе — у него
     «яХожу» стоит, а «могуПодкинуть» снято.

     Раньше здесь было написано, будто «могуПодкинуть» означает лишь
     «есть чем», и прогон это поле не смотрел вовсе. Из-за этого он слал
     ход и за спасовавших, получал отказ — и списывал его на свою
     недоработку. Поле с тех пор починено и значит ровно то, что сказано
     выше, так что теперь мы на него и опираемся. */
  if (вид.яХожу) {
    /* Карт на руках нет, а слово наше — так бывает в самом конце партии:
       свои карты мы выложили, но подход ещё идёт, и закрыть его должны мы.
       Живой игрок в этот миг видит кнопку «Бито» и жмёт её. Раньше прогон
       тут просто молчал, стол замирал на четыре секунды, и «Бито» уходило
       уже как проба на замерший стол — то есть проверка сама создавала
       себе поломку на здоровом коде. */
    if (!рука.length) {
      return стол.length
        ? { намерение: { действие: 'бито' }, жалоба: null }
        : { намерение: null, жалоба: null };
    }

    if (!вид.могуПодкинуть) {
      /* Класть не вправе — остаётся закрыть подход. Но если стол пуст,
         это уже противоречие: ходящему с пустым столом класть карту
         не просто можно, а нужно — больше сходить нечем. */
      if (!стол.length) {
        return {
          намерение: null,
          жалоба: 'показано «ваш ход» при пустом столе, но положить карту игрок не вправе ' +
                  '(могуПодкинуть: false) — ходить ему нечем и подход не закрыть'
        };
      }
      return { намерение: { действие: 'бито' }, жалоба: null };
    }

    if (!стол.length) {
      // ходим самой слабой некозырной картой
      const порядок = рука.map((к, i) => ({ к, i }))
        .sort((а, б) => (а.к.масть === козырь ? 1 : 0) - (б.к.масть === козырь ? 1 : 0) || а.к.вес - б.к.вес);
      return { намерение: { действие: 'ходить', карта: порядок[0].i }, жалоба: null };
    }

    /* Два ограничения подкидывания считаем сами, по тому же столу,
       который видит живой игрок: больше шести карт за подход не кладут,
       и неотбитых не может стать больше, чем карт в руке у того, кто
       отбивается. Раньше прогон их не знал, посылал такой ход и разбирал
       ответ сервера по словам причины — а слова могут поменяться в любой
       день, и проверка покраснеет на здоровом коде. */
    const картУЗащитника = картУОтбивающегося(вид);
    const местаНет = стол.length >= МАКС_КАРТ_В_ПОДХОДЕ ||
      (картУЗащитника !== null && сколькоНеотбитых(стол) >= картУЗащитника);
    if (местаНет) return { намерение: { действие: 'бито' }, жалоба: null };

    // подкидываем то, что уже лежит по достоинству
    const веса = new Set();
    стол.forEach((п) => {
      if (п.атака) веса.add(п.атака.вес);
      if (п.защита) веса.add(п.защита.вес);
    });
    const годная = рука.findIndex((к) => веса.has(к.вес) && к.масть !== козырь);
    if (годная >= 0) return { намерение: { действие: 'ходить', карта: годная }, жалоба: null };
    return { намерение: { действие: 'бито' }, жалоба: null };
  }

  return { намерение: null, жалоба: null };
}

