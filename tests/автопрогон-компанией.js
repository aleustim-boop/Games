async function главная() {
  console.log('Автопрогон партий компанией. Сервер: ' + ХОЗЯИН + ':' + ПОРТ);
  console.log('Партий на каждую раскладку: ' + ПАРТИЙ_НА_РАСКЛАДКУ);
  console.log('');

  const бедыСамопроверки = проверитьСамогоСебя();
  if (бедыСамопроверки.length) {
    console.log('САМОПРОВЕРКА НЕ ПРОШЛА — играть таким прогоном бессмысленно:');
    бедыСамопроверки.forEach((т) => console.log('  * ' + т));
    process.exitCode = 1;
    return;
  }
  console.log('Самопроверка: решения принимаются по полям состояния (6 случаев) — в порядке.');
  console.log('');

  let всегоБед = 0;
  for (const раскладка of РАСКЛАДКИ) {
    let сыграно = 0;
    const бедыРаскладки = [];
    const итоги = {};
    for (let i = 0; i < ПАРТИЙ_НА_РАСКЛАДКУ; i++) {
      let результат;
      try {
        результат = await сыгратьПартию(раскладка, i + 1);
      } catch (сбой) {
        результат = { беды: [{ что: 'сорвалось: ' + сбой.message }], итог: null };
      }
      сыграно++;
      if (результат.итог && результат.итог.итог) {
        итоги[результат.итог.итог] = (итоги[результат.итог.итог] || 0) + 1;
      }
      результат.беды.forEach((б) => бедыРаскладки.push(Object.assign({ партия: i + 1 }, б)));
      await пауза(80);
    }
    всегоБед += бедыРаскладки.length;
    console.log('— ' + раскладка.имя + ': сыграно ' + сыграно +
      ', итоги ' + JSON.stringify(итоги) +
      ', поломок ' + бедыРаскладки.length);
    бедыРаскладки.slice(0, 4).forEach((б) => {
      console.log('    партия ' + б.партия + ': ' + б.что +
        (б.причина ? ' — «' + б.причина + '»' : '') +
        (б.намерение ? ' (действие: ' + JSON.stringify(б.намерение) + ')' : ''));
      // Показываем и само состояние: без него поломку не повторить руками.
      if (б.вид) console.log('        состояние: ' + JSON.stringify(б.вид));
    });
  }

  console.log('');
  console.log(всегоБед ? 'ИТОГ: поломок ' + всегоБед : 'ИТОГ: поломок не нашлось');
}

главная().catch((сбой) => {
  console.error('Автопрогон сорвался: ' + сбой.message);
  process.exitCode = 1;
});
