async function сыгратьПартию(раскладка, номерПартии) {
  const беды = [];
  const создано = await спросить('/создать', {
    мест: раскладка.мест, переводной: раскладка.переводной, парами: раскладка.парами, имя: 'Проверка'
  });
  if (создано.код !== 200 || !создано.тело.код) {
    return { беды: [{ что: 'комната не создалась', ответ: создано }], итог: null };
  }
  const код = создано.тело.код;
  const пропуск = создано.тело.пропуск;

  // сажаем ботов на все свободные места
  for (let i = 0; i < раскладка.мест - 1; i++) {
    const о = await спросить('/ход', { код, пропуск, действие: 'бот' });
    if (о.код !== 200 || (о.тело && о.тело.принято === false)) {
      беды.push({ что: 'бот не сел', номер: i + 1, ответ: о.тело });
    }
  }

  const начали = await спросить('/ход', { код, пропуск, действие: 'начать' });
  if (начали.код !== 200 || (начали.тело && начали.тело.принято === false)) {
    беды.push({ что: 'игра не началась', ответ: начали.тело });
    return { беды, итог: null };
  }

  let итог = null;
  let действий = 0;
  let последнееШевеление = Date.now();
  let прошлыйСлепок = '';

  while (действий < ПОТОЛОК_ДЕЙСТВИЙ) {
    const с = await спросить('/состояние', { код, пропуск });
    if (с.код !== 200) {
      беды.push({ что: 'сервер потерял комнату посреди партии', код: с.код, ответ: с.тело, действий });
      break;
    }
    const вид = с.тело && с.тело.состояние ? с.тело.состояние : с.тело;
    if (вид.завершена) {
      итог = {
        итог: вид.итог,
        проигравшие: (вид.застолом || []).filter((м) => м.проиграл).map((м) => м.имя)
      };
      break;
    }

    const намерение = решить(вид);
    const слепок = JSON.stringify([вид.стол, вид.мояРука.length, вид.яХожу, вид.яОтбиваюсь, вид.берут]);
    if (слепок !== прошлыйСлепок) { прошлыйСлепок = слепок; последнееШевеление = Date.now(); }

    if (!намерение) {
      /* Стол долго не шевелится. Может быть, ждут именно нас: в компании
         слово «пасовать» обходит всех по кругу, и признак «я хожу» в этот
         миг у нас не стоит. Пробуем сказать «бито» — если сервер примет,
         значит ждали нас, и это не поломка. */
      if (Date.now() - последнееШевеление > 4000) {
        const проба = await спросить('/ход', { код, пропуск, действие: 'бито' });
        if (проба.код === 200 && проба.тело && проба.тело.принято) {
          последнееШевеление = Date.now();
          действий++;
          await пауза(200);
          continue;
        }
      }
      if (Date.now() - последнееШевеление > ЖДЁМ_БОТОВ_МС) {
        беды.push({ что: 'партия замерла: ходить некому', вид: краткоВид(вид), действий });
        break;
      }
      await пауза(250);
      continue;
    }

    const о = await спросить('/ход', Object.assign({ код, пропуск }, намерение));
    действий++;
    if (о.код !== 200) {
      беды.push({ что: 'сервер ответил ошибкой на ход', код: о.код, намерение, ответ: о.тело });
      break;
    }
    if (о.тело && о.тело.принято === false) {
      /* Отказ по правилам подкидывания — это не поломка игры, а наша
         недоработка: подкидывать больше, чем у отбивающегося карт, нельзя.
         Такие случаи просто заканчиваем «бито» и идём дальше. */
      const этоПравилоПодкидывания = /подкид|меньше карт/i.test(о.тело.причина || '');
      if (этоПравилоПодкидывания) {
        await спросить('/ход', { код, пропуск, действие: 'бито' });
      } else {
        беды.push({ что: 'сервер отказал на разрешённое действие', намерение, причина: о.тело.причина, вид: краткоВид(вид) });
      }
      await пауза(200);
    }
    последнееШевеление = Date.now();
  }

  if (!итог && !беды.length) {
    беды.push({ что: 'партия не кончилась за ' + ПОТОЛОК_ДЕЙСТВИЙ + ' действий' });
  }
  if (итог && !итог.итог) {
    беды.push({ что: 'партия кончилась, а итога нет', итог });
  }
  if (итог && итог.итог && итог.итог !== 'ничья' && !итог.проигравшие.length) {
    беды.push({ что: 'партия кончилась, а дурак не назван', итог });
  }
  if (итог && раскладка.парами && итог.проигравшие.length === 1) {
    беды.push({ что: 'игра парами, а проиграл один, не пара', итог });
  }

  await спросить('/выйти', { код, пропуск });
  return { беды, итог, действий, код };
}

function краткоВид(вид) {
  return {
    фаза: вид.фаза, яХожу: вид.яХожу, яОтбиваюсь: вид.яОтбиваюсь,
    могуПодкинуть: вид.могуПодкинуть, берут: вид.берут,
    вКолоде: вид.вКолоде, картВРуке: (вид.мояРука || []).length,
    паруНаСтоле: (вид.стол || []).length,
    застолом: (вид.застолом || []).map((м) => м.имя + ':' + м.карт +
      (м.ходит ? ' (ходит)' : '') + (м.отбивается ? ' (отбивается)' : '') + (м.выбыл ? ' (вышел)' : ''))
  };
}

