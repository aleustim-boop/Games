// Проверка: строка «Язык» в общем листе «⋯» (общее/js/лист-ещё.js).
//
// Запуск:
//   node tests/лист-язык.js                — обычный прогон, ждём 0 провалов
//   node tests/лист-язык.js --лист <путь>  — тот же набор на копии листа по пути
//   node tests/лист-язык.js --сломать      — ломающие запуски: каждая порча копии
//     листа (во временной папке) обязана покраснеть; файл проекта не трогаем
//
// Страницы нет: лист грузится в песочницу vm с поддельным документом.
// Ноль найденных узлов — провал, не пропуск.

const fs = require('fs');
const os = require('os');
const path = require('path');
const vm = require('vm');
const { spawnSync } = require('child_process');
const { сделатьДокумент } = require('./поддельный-браузер.js');

const КОРЕНЬ = path.join(__dirname, '..');
const ФАЙЛ_ЛИСТА = path.join(КОРЕНЬ, 'общее', 'js', 'лист-ещё.js');
const ID_ЯЗЫК = 'кнопка-лист-игры-язык';

function довод(имя) {
  const и = process.argv.indexOf(имя);
  return и !== -1 ? process.argv[и + 1] : null;
}

/** Поддельный переключатель языка: круг ru → uk → en, названия как у настоящего. */
function сделатьЯзык() {
  const круг = ['ru', 'uk', 'en'];
  const названия = { ru: 'Русский', uk: 'Українська', en: 'English' };
  const я = { код: 'ru', нажатий: 0 };
  я.api = {
    следующий: function () { я.нажатий++; я.код = круг[(круг.indexOf(я.код) + 1) % 3]; return я.код; },
    название: function () { return названия[я.код]; }
  };
  return я;
}

/** Лист как у игры: все прежние строки (в т.ч. вибрация и оформление) + «Закрыть». */
function собрать(путьКЛисту, сЯзыком) {
  const документ = сделатьДокумент();
  const модуль = { exports: {} };
  const язык = сделатьЯзык();
  const песочница = { module: модуль, exports: модуль.exports, console: console, document: документ,
    setTimeout: setTimeout, clearTimeout: clearTimeout, window: {} };
  if (сЯзыком) песочница.window.ЯзыкИнтерфейса = язык.api;
  vm.createContext(песочница);
  vm.runInContext(fs.readFileSync(путьКЛисту, 'utf8'), песочница, { filename: путьКЛисту + ' (в памяти)' });
  const Лист = модуль.exports;
  документ.body.appendChild(документ.узел('button', { id: 'кнопка-игра-ещё' }));
  const колонка = документ.узел('div', { класс: 'лист-ещё__лист' });
  [['кнопка-лист-игры-меню', 'В меню'], ['кнопка-лист-игры-правила', 'Как играть'],
   ['кнопка-лист-игры-звук', 'Звук'], ['кнопка-лист-игры-вибрация', 'Вибрация'],
   ['кнопка-лист-игры-оформление', 'Оформление'], ['кнопка-лист-игры-рекорды', 'Рекорды']].forEach(function (п) {
    колонка.appendChild(документ.узел('button', { id: п[0], класс: 'лист-ещё__строка' },
      документ.узел('span', { класс: 'лист-ещё__подпись', текст: п[1] })));
  });
  колонка.appendChild(документ.узел('button', { класс: 'лист-ещё__закрыть' }));
  документ.body.appendChild(документ.узел('div', { id: 'лист-игры', класс: 'лист-ещё скрыт' },
    документ.узел('div', { id: 'лист-игры-фон' }), колонка));
  const пусто = function () {};
  const двери = {
    вМеню: { действие: пусто }, какИграть: { действие: пусто },
    звук: { действие: пусто, состояние: function () { return 'вкл'; } },
    вибрация: { действие: пусто, доступна: function () { return true; }, состояние: function () { return 'вкл'; } },
    оформление: { действие: пусто }, рекорды: { действие: пусто }
  };
  const управление = Лист.подключить({ двери: двери });
  return { Лист: Лист, документ: документ, колонка: колонка, двери: двери, управление: управление, язык: язык };
}

function видимые(сц) {
  return сц.колонка.children
    .filter(function (у) { return у.classList.contains('лист-ещё__строка') && !у.classList.contains('скрыт'); })
    .map(function (у) { return у.id; });
}

function прогнать(путьКЛисту) {
  const итоги = { всего: 0, провалов: 0 };
  function надо(условие, что) {
    итоги.всего++;
    if (!условие) { итоги.провалов++; console.log('  ПРОВАЛ: ' + что); }
  }
  const ОЖИДАЕМО = ['кнопка-лист-игры-меню', 'кнопка-лист-игры-правила', 'кнопка-лист-игры-звук',
    'кнопка-лист-игры-вибрация', ID_ЯЗЫК, 'кнопка-лист-игры-оформление', 'кнопка-лист-игры-рекорды'];

  // 1. Переключатель языка есть — строка между «Вибрация» и «Оформление».
  const с = собрать(путьКЛисту, true);
  с.управление.открыть();
  надо(JSON.stringify(видимые(с)) === JSON.stringify(ОЖИДАЕМО), 'с языком: порядок строк ' + JSON.stringify(видимые(с)));
  const чистые = с.Лист.строкиЛиста(с.двери).map(function (р) { return р.id; });
  const и = чистые.indexOf(ID_ЯЗЫК);
  надо(и !== -1, 'с языком: строкиЛиста отдаёт строку «Язык»');
  надо(и > 0 && чистые[и - 1] === 'кнопка-лист-игры-вибрация' && чистые[и + 1] === 'кнопка-лист-игры-оформление',
    'с языком: в строкиЛиста «Язык» между вибрацией и оформлением');
  const узел = с.документ.getElementById(ID_ЯЗЫК);
  надо(узел !== null, 'с языком: узел строки создан');
  надо(Boolean(узел) && узел.classList.contains('лист-ещё__строка'), 'у строки общий класс строки листа');
  надо(Boolean(узел) && узел.textContent.indexOf('Язык') === 0, 'подпись «Язык» слева');
  const значение = с.документ.getElementById('лист-игры-язык-состояние');
  надо(значение !== null && значение.textContent === 'Русский', 'справа название текущего языка (Русский)');
  надо(значение !== null && значение.hasAttribute('data-no-translate'), 'название языка помечено data-no-translate');
  надо(значение !== null && значение.classList.contains('лист-ещё__значение'), 'название языка — общий класс значения');

  // 2. Нажатие листает по кругу и лист не закрывает.
  const ждём = ['Українська', 'English', 'Русский'];
  ждём.forEach(function (имя, номер) {
    if (узел) узел.click();
    надо(с.язык.нажатий === номер + 1, 'нажатие ' + (номер + 1) + ': переключатель позван ровно раз');
    надо(значение !== null && значение.textContent === имя, 'нажатие ' + (номер + 1) + ': справа «' + имя + '»');
    надо(с.управление.открыт() === true, 'нажатие ' + (номер + 1) + ': лист остался открытым');
  });

  // 3. Нет ЯзыкаИнтерфейса — строки нет совсем.
  const без = собрать(путьКЛисту, false);
  без.управление.открыть();
  надо(без.документ.getElementById(ID_ЯЗЫК) === null, 'без языка: узла строки нет в документе');
  надо(без.Лист.строкиЛиста(без.двери).every(function (р) { return р.id !== ID_ЯЗЫК; }), 'без языка: строкиЛиста без «Язык»');
  надо(видимые(без).length === ОЖИДАЕМО.length - 1, 'без языка: остальные 6 строк на месте (' + видимые(без).length + ')');

  // 4. Словарь: добавить() и добавитьШаблоны() (общее/js/языки.js) работают.
  const Языки = require(path.join(КОРЕНЬ, 'общее', 'js', 'языки.js'));
  надо(typeof Языки.добавить === 'function' && typeof Языки.добавитьШаблоны === 'function', 'языки.js отдаёт добавить и добавитьШаблоны');
  надо(Языки.текст('Язык', 'uk') === 'Мова' && Языки.текст('Язык', 'en') === 'Language', 'в словаре есть «Язык»');
  if (typeof Языки.добавить === 'function') Языки.добавить('Тестовая фраза|Тестова фраза|Test phrase');
  надо(Языки.текст('Тестовая фраза', 'en') === 'Test phrase', 'добавить() дописывает строку словаря');
  if (typeof Языки.добавитьШаблоны === 'function') Языки.добавитьШаблоны([[/^Тест (\d+) шт$/, 'Тест $1 шт.', 'Test $1 pcs']]);
  надо(Языки.текст('Тест 5 шт', 'en') === 'Test 5 pcs', 'добавитьШаблоны() дописывает шаблон (en)');

  console.log('Итого проверок: ' + итоги.всего + ', провалов: ' + итоги.провалов);
  return итоги;
}

