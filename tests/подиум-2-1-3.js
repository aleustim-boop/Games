/** Подождать один оборот реального цикла событий Node — фетч и цепочка
    промисов внутри «спроситьТаблицу» успевают разрешиться до того,
    как проверка полезет смотреть в DOM. */
function ждатьТик(мс) {
  return new Promise(function (resolve) { setTimeout(resolve, мс || 40); });
}

/** Найти строку таблицы рейтинга по номеру места (атрибут data-место).
    Общий помощник для проверок стрелки движения — строки ищутся по
    месту, а не по индексу в списке узлов: порядок узлов на странице
    (подиум, потом обычные строки, потом своя строка внизу) — дело
    разметки, проверке важно только «какое место у этой строки». */
function строкаПоМесту(таблица, место) {
  if (!таблица) return null;
  const строки = Array.prototype.slice.call(таблица.querySelectorAll('.рейтинг-строка'));
  for (let и = 0; и < строки.length; и++) {
    if (строки[и].getAttribute('data-место') === String(место)) return строки[и];
  }
  return null;
}

/**
 * Часть 1: чистые функции без DOM — «тройкаНаПодиум» и «видПоОтвету»
 * (поле «лидерыПодПодиумом»). Модуль читаем обычным require: без document
 * файл ведёт себя как чистая библиотека (см. в конце файла условие
 * «typeof document !== 'undefined'» — при его отсутствии подключение
 * к странице просто не происходит), это тот же приём, что и в
 * tests/рейтинг-экран-четыре-игры.js.
 */
function проверитьЧистыеФункции(модуль, проверить) {
  const тройкаНаПодиум = модуль.тройкаНаПодиум;
  const видПоОтвету = модуль.видПоОтвету;

  проверить('модуль экспортирует функцию тройкаНаПодиум', typeof тройкаНаПодиум === 'function');
  проверить('модуль экспортирует функцию видПоОтвету', typeof видПоОтвету === 'function');
  if (typeof тройкаНаПодиум !== 'function') return;

  /* 5 лидеров — полная тройка, порядок отрисовки 2-1-3 */
  const лидеры5 = [
    { место: 1, имя: 'Первый', очки: 100 },
    { место: 2, имя: 'Второй', очки: 90 },
    { место: 3, имя: 'Третий', очки: 80 },
    { место: 4, имя: 'Четвёртый', очки: 70 },
    { место: 5, имя: 'Пятый', очки: 60 }
  ];
  let подиум5 = [];
  try {
    подиум5 = тройкаНаПодиум(лидеры5);
  } catch (сбой) {
    проверить('тройкаНаПодиум(5 лидеров) не падает: ' + сбой.message, false);
  }
  проверить('тройкаНаПодиум(5 лидеров): ровно три карточки',
    Array.isArray(подиум5) && подиум5.length === 3);
  проверить('тройкаНаПодиум(5 лидеров): порядок отрисовки мест 2,1,3',
    Array.isArray(подиум5) && подиум5.length === 3 &&
    подиум5[0].место === 2 && подиум5[1].место === 1 && подиум5[2].место === 3);

  /* 2 лидера — только 2 и 1, третьего места нет вовсе */
  const лидеры2 = [
    { место: 1, имя: 'Первый', очки: 100 },
    { место: 2, имя: 'Второй', очки: 90 }
  ];
  const подиум2 = тройкаНаПодиум(лидеры2);
  проверить('тройкаНаПодиум(2 лидера): ровно две карточки',
    Array.isArray(подиум2) && подиум2.length === 2);
  проверить('тройкаНаПодиум(2 лидера): порядок отрисовки мест 2,1',
    Array.isArray(подиум2) && подиум2.length === 2 &&
    подиум2[0].место === 2 && подиум2[1].место === 1);

  /* 1 лидер — только первое место */
  const лидеры1 = [{ место: 1, имя: 'Первый', очки: 100 }];
  const подиум1 = тройкаНаПодиум(лидеры1);
  проверить('тройкаНаПодиум(1 лидер): одна карточка, место 1',
    Array.isArray(подиум1) && подиум1.length === 1 && подиум1[0].место === 1);

  /* 0 лидеров — пусто, и мусор вместо массива не роняет функцию */
  проверить('тройкаНаПодиум(0 лидеров): пустой массив',
    Array.isArray(тройкаНаПодиум([])) && тройкаНаПодиум([]).length === 0);
  проверить('тройкаНаПодиум(мусор вместо массива — null): не падает, пусто',
    (function () {
      try { return Array.isArray(тройкаНаПодиум(null)) && тройкаНаПодиум(null).length === 0; }
      catch (сбой) { return false; }
    })());

  /* Строка с место === null пропускается, не портит остальные три места */
  const лидерыСДыркой = [
    { место: null, имя: 'Без места', очки: 5 },
    { место: 1, имя: 'Первый', очки: 100 },
    { место: 2, имя: 'Второй', очки: 90 },
    { место: 3, имя: 'Третий', очки: 80 }
  ];
  const подиумСДыркой = тройкаНаПодиум(лидерыСДыркой);
  проверить('тройкаНаПодиум: строка без места (место=null) на подиум не попадает',
    Array.isArray(подиумСДыркой) && подиумСДыркой.every(function (к) { return к && к.место !== null; }));
  проверить('тройкаНаПодиум: несмотря на строку без места, три остальные карточки в порядке 2,1,3',
    Array.isArray(подиумСДыркой) && подиумСДыркой.length === 3 &&
    подиумСДыркой[0].место === 2 && подиумСДыркой[1].место === 1 && подиумСДыркой[2].место === 3);

  if (typeof видПоОтвету !== 'function') return;

  /* «лидерыПодПодиумом» через видПоОтвету: пять лидеров, «я» — второе
     место (значит, в тройке). Список под подиумом не должен повторять
     тройку и обязан начинаться с 4-го места. */
  const ответПятиЛидеров = {
    беда: null,
    данные: {
      узналиВас: true, всего: 5, яВТаблице: true,
      я: { место: 2, имя: 'Я', очки: 90, побед: 3, партий: 5, этоЯ: true },
      верхушка: [
        { место: 1, имя: 'Первый', очки: 100, побед: 10, партий: 10 },
        { место: 2, имя: 'Я', очки: 90, побед: 3, партий: 5, этоЯ: true },
        { место: 3, имя: 'Третий', очки: 80, побед: 2, партий: 5 },
        { место: 4, имя: 'Четвёртый', очки: 70, побед: 1, партий: 5 },
        { место: 5, имя: 'Пятый', очки: 60, побед: 1, партий: 5 }
      ],
      вокругМеня: [{ место: 2, имя: 'Я', очки: 90, побед: 3, партий: 5, этоЯ: true }]
    }
  };
  let видПять = null;
  try {
    видПять = видПоОтвету(ответПятиЛидеров, 'очки');
  } catch (сбой) {
    проверить('видПоОтвету(5 лидеров, мера очки) не падает: ' + сбой.message, false);
  }
  if (видПять) {
    проверить('видПоОтвету: поле «подиум» — массив из трёх карточек',
      Array.isArray(видПять.подиум) && видПять.подиум.length === 3);
    проверить('видПоОтвету: поле «лидерыПодПодиумом» — массив',
      Array.isArray(видПять.лидерыПодПодиумом));
    if (Array.isArray(видПять.подиум) && Array.isArray(видПять.лидерыПодПодиумом)) {
      const местаПодиума = видПять.подиум.map(function (к) { return к.место; });
      const пересекается = видПять.лидерыПодПодиумом.some(function (с) {
        return местаПодиума.indexOf(с.место) !== -1;
      });
      проверить('видПоОтвету: «лидерыПодПодиумом» не пересекается с «подиум»', !пересекается);
      проверить('видПоОтвету: при пяти лидерах «лидерыПодПодиумом» начинается с 4-го места',
        видПять.лидерыПодПодиумом.length > 0 && видПять.лидерыПодПодиумом[0].место === 4);
    }
  }

  /* Пусто — и подиум, и список под ним пустые по-настоящему, а не потому,
     что проверка ничего не нашла и промолчала. */
  const ответПусто = { беда: null, данные: { узналиВас: true, всего: 0, верхушка: [], вокругМеня: [] } };
  let видПусто = null;
  try {
    видПусто = видПоОтвету(ответПусто, 'очки');
  } catch (сбой) {
    проверить('видПоОтвету(пусто) не падает: ' + сбой.message, false);
  }
  if (видПусто) {
    проверить('видПоОтвету(пусто): «подиум» — пустой массив',
      Array.isArray(видПусто.подиум) && видПусто.подиум.length === 0);
    проверить('видПоОтвету(пусто): «лидерыПодПодиумом» — пустой массив',
      Array.isArray(видПусто.лидерыПодПодиумом) && видПусто.лидерыПодПодиумом.length === 0);
  }
}

