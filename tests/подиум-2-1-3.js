'use strict';

/* =====================================================================
   Проверка тестировщика: подиум первой тройки на экране рейтинга.

   Что проверяем и почему именно так.
   Разработчик сдал функцию «тройкаНаПодиум» (js/рейтинг-экран.js, чистая
   функция без DOM — на входе список лидеров, на выходе три карточки
   в порядке отрисовки 2-1-3) и рисование этого подиума первым узлом
   внутри #рейтинг-таблица. Первую часть (саму логику «кто где стоит»)
   можно проверить голым require — без браузера. Вторую часть (что
   ДЕЙСТВИТЕЛЬНО появляется на странице: сколько карточек, в каком
   порядке, у кого класс «это я») голым require не увидеть — там нужен
   настоящий DOM. Поэтому эта проверка поднимает весь js/рейтинг-экран.js
   в поддельном браузере (tests/поддельный-браузер.js — тот же приём,
   что и в других проверках экранов), подсовывает ему поддельный fetch
   вместо сервера и смотрит на итоговые узлы страницы.

   Устройство подиума проверка читает из того же файла, что его рисует:
   имена классов (.рейтинг-подиум, .рейтинг-подиум-карточка,
   .рейтинг-подиум-имя, .рейтинг-подиум-очки, .рейтинг-подиум-карточка--я)
   и порядок отрисовки 2-1-3 — не вторая копия чисел, а те же строки,
   что в js/рейтинг-экран.js (см. «подиумУзел», «карточкаПодиума»,
   «тройкаНаПодиум»). Второй копии этих селекторов в этом файле нет:
   если разработчик переименует класс, а разметку не поправит — проверка
   покажет реальную поломку, а не сравнение одной опечатки с другой.

   Запуск чистого прогона:
       node tests/подиум-2-1-3.js

   Ломающий запуск — проверка ОБЯЗАНА покраснеть на испорченной копии
   (настоящий файл проекта эта проверка никогда не трогает и не портит):
       node tests/подиум-2-1-3.js --сломать <путь-к-испорченной-копии-js>
   Путь к копии проверка получает доводом командной строки, а не решает
   сама, где и как портить файл, — портить копию (и решать, ЧТО именно
   в ней сломано) дело того, кто зовёт ломающий запуск. Гоняются ТЕ ЖЕ
   проверки, что и в чистом прогоне, никакого отдельного мини-набора.
   ===================================================================== */

const fs = require('fs');
const path = require('path');

const бр = require(path.join(__dirname, 'поддельный-браузер.js'));

const КОРЕНЬ = path.join(__dirname, '..');
const ПУТЬ_ПО_УМОЛЧАНИЮ = path.join(КОРЕНЬ, 'js', 'рейтинг-экран.js');

/** Подождать один оборот реального цикла событий Node — фетч и цепочка
    промисов внутри «спроситьТаблицу» успевают разрешиться до того,
    как проверка полезет смотреть в DOM. */
function ждатьТик(мс) {
  return new Promise(function (resolve) { setTimeout(resolve, мс || 40); });
}

/**
 * Часть 1: чистые функции без DOM — «тройкаНаПодиум» и «видПоОтвету»
 * (поле «лидерыПодПодиумом»). Модуль читаем обычным require: без document
 * файл ведёт себя как чистая библиотека (см. в конце файла условие
 * «typeof document !== 'undefined'» — при его отсутствии подключение
 * к странице просто не происходит), это тот же приём, что и в
 * tests/рейтинг-экран-четыре-игры.js.
 */
function проверитьЧистыеФункции(модуль, проверить) {
  const тройкаНаПодиум = модуль.тройкаНаПодиум;
  const видПоОтвету = модуль.видПоОтвету;

  проверить('модуль экспортирует функцию тройкаНаПодиум', typeof тройкаНаПодиум === 'function');
  проверить('модуль экспортирует функцию видПоОтвету', typeof видПоОтвету === 'function');
  if (typeof тройкаНаПодиум !== 'function') return;

  /* 5 лидеров — полная тройка, порядок отрисовки 2-1-3 */
  const лидеры5 = [
    { место: 1, имя: 'Первый', очки: 100 },
    { место: 2, имя: 'Второй', очки: 90 },
    { место: 3, имя: 'Третий', очки: 80 },
    { место: 4, имя: 'Четвёртый', очки: 70 },
    { место: 5, имя: 'Пятый', очки: 60 }
  ];
  let подиум5 = [];
  try {
    подиум5 = тройкаНаПодиум(лидеры5);
  } catch (сбой) {
    проверить('тройкаНаПодиум(5 лидеров) не падает: ' + сбой.message, false);
  }
  проверить('тройкаНаПодиум(5 лидеров): ровно три карточки',
    Array.isArray(подиум5) && подиум5.length === 3);
  проверить('тройкаНаПодиум(5 лидеров): порядок отрисовки мест 2,1,3',
    Array.isArray(подиум5) && подиум5.length === 3 &&
    подиум5[0].место === 2 && подиум5[1].место === 1 && подиум5[2].место === 3);

  /* 2 лидера — только 2 и 1, третьего места нет вовсе */
  const лидеры2 = [
    { место: 1, имя: 'Первый', очки: 100 },
    { место: 2, имя: 'Второй', очки: 90 }
  ];
  const подиум2 = тройкаНаПодиум(лидеры2);
  проверить('тройкаНаПодиум(2 лидера): ровно две карточки',
    Array.isArray(подиум2) && подиум2.length === 2);
  проверить('тройкаНаПодиум(2 лидера): порядок отрисовки мест 2,1',
    Array.isArray(подиум2) && подиум2.length === 2 &&
    подиум2[0].место === 2 && подиум2[1].место === 1);

  /* 1 лидер — только первое место */
  const лидеры1 = [{ место: 1, имя: 'Первый', очки: 100 }];
  const подиум1 = тройкаНаПодиум(лидеры1);
  проверить('тройкаНаПодиум(1 лидер): одна карточка, место 1',
    Array.isArray(подиум1) && подиум1.length === 1 && подиум1[0].место === 1);

  /* 0 лидеров — пусто, и мусор вместо массива не роняет функцию */
  проверить('тройкаНаПодиум(0 лидеров): пустой массив',
    Array.isArray(тройкаНаПодиум([])) && тройкаНаПодиум([]).length === 0);
  проверить('тройкаНаПодиум(мусор вместо массива — null): не падает, пусто',
    (function () {
      try { return Array.isArray(тройкаНаПодиум(null)) && тройкаНаПодиум(null).length === 0; }
      catch (сбой) { return false; }
    })());

  /* Строка с место === null пропускается, не портит остальные три места */
  const лидерыСДыркой = [
    { место: null, имя: 'Без места', очки: 5 },
    { место: 1, имя: 'Первый', очки: 100 },
    { место: 2, имя: 'Второй', очки: 90 },
    { место: 3, имя: 'Третий', очки: 80 }
  ];
  const подиумСДыркой = тройкаНаПодиум(лидерыСДыркой);
  проверить('тройкаНаПодиум: строка без места (место=null) на подиум не попадает',
    Array.isArray(подиумСДыркой) && подиумСДыркой.every(function (к) { return к && к.место !== null; }));
  проверить('тройкаНаПодиум: несмотря на строку без места, три остальные карточки в порядке 2,1,3',
    Array.isArray(подиумСДыркой) && подиумСДыркой.length === 3 &&
    подиумСДыркой[0].место === 2 && подиумСДыркой[1].место === 1 && подиумСДыркой[2].место === 3);

  if (typeof видПоОтвету !== 'function') return;

  /* «лидерыПодПодиумом» через видПоОтвету: пять лидеров, «я» — второе
     место (значит, в тройке). Список под подиумом не должен повторять
     тройку и обязан начинаться с 4-го места. */
  const ответПятиЛидеров = {
    беда: null,
    данные: {
      узналиВас: true, всего: 5, яВТаблице: true,
      я: { место: 2, имя: 'Я', очки: 90, побед: 3, партий: 5, этоЯ: true },
      верхушка: [
        { место: 1, имя: 'Первый', очки: 100, побед: 10, партий: 10 },
        { место: 2, имя: 'Я', очки: 90, побед: 3, партий: 5, этоЯ: true },
        { место: 3, имя: 'Третий', очки: 80, побед: 2, партий: 5 },
        { место: 4, имя: 'Четвёртый', очки: 70, побед: 1, партий: 5 },
        { место: 5, имя: 'Пятый', очки: 60, побед: 1, партий: 5 }
      ],
      вокругМеня: [{ место: 2, имя: 'Я', очки: 90, побед: 3, партий: 5, этоЯ: true }]
    }
  };
  let видПять = null;
  try {
    видПять = видПоОтвету(ответПятиЛидеров, 'очки');
  } catch (сбой) {
    проверить('видПоОтвету(5 лидеров, мера очки) не падает: ' + сбой.message, false);
  }
  if (видПять) {
    проверить('видПоОтвету: поле «подиум» — массив из трёх карточек',
      Array.isArray(видПять.подиум) && видПять.подиум.length === 3);
    проверить('видПоОтвету: поле «лидерыПодПодиумом» — массив',
      Array.isArray(видПять.лидерыПодПодиумом));
    if (Array.isArray(видПять.подиум) && Array.isArray(видПять.лидерыПодПодиумом)) {
      const местаПодиума = видПять.подиум.map(function (к) { return к.место; });
      const пересекается = видПять.лидерыПодПодиумом.some(function (с) {
        return местаПодиума.indexOf(с.место) !== -1;
      });
      проверить('видПоОтвету: «лидерыПодПодиумом» не пересекается с «подиум»', !пересекается);
      проверить('видПоОтвету: при пяти лидерах «лидерыПодПодиумом» начинается с 4-го места',
        видПять.лидерыПодПодиумом.length > 0 && видПять.лидерыПодПодиумом[0].место === 4);
    }
  }

  /* Пусто — и подиум, и список под ним пустые по-настоящему, а не потому,
     что проверка ничего не нашла и промолчала. */
  const ответПусто = { беда: null, данные: { узналиВас: true, всего: 0, верхушка: [], вокругМеня: [] } };
  let видПусто = null;
  try {
    видПусто = видПоОтвету(ответПусто, 'очки');
  } catch (сбой) {
    проверить('видПоОтвету(пусто) не падает: ' + сбой.message, false);
  }
  if (видПусто) {
    проверить('видПоОтвету(пусто): «подиум» — пустой массив',
      Array.isArray(видПусто.подиум) && видПусто.подиум.length === 0);
    проверить('видПоОтвету(пусто): «лидерыПодПодиумом» — пустой массив',
      Array.isArray(видПусто.лидерыПодПодиумом) && видПусто.лидерыПодПодиумом.length === 0);
  }
}

/**
 * Часть 2: настоящий DOM в поддельном браузере. Поднимаем весь
 * js/рейтинг-экран.js в песочнице vm (tests/поддельный-браузер.js),
 * подсовываем поддельный fetch вместо сервера и зовём единственную
 * публичную дверь window.ЭкранРейтинга.открыть(...) — тем же путём,
 * каким приходит настоящий игрок. Дальше смотрим, что фактически лежит
 * внутри #рейтинг-таблица.
 */
async function проверитьDOM(исходник, проверить) {
  const ответУспех = {
    ок: true, узналиВас: true, всего: 5, яВТаблице: true,
    я: { место: 2, имя: 'Я Игрок', очки: 90, побед: 3, партий: 5, этоЯ: true },
    верхушка: [
      { место: 1, имя: 'Первый', очки: 100, побед: 10, партий: 10 },
      { место: 2, имя: 'Я Игрок', очки: 90, побед: 3, партий: 5, этоЯ: true },
      { место: 3, имя: 'Третий', очки: 80, побед: 2, партий: 5 },
      { место: 4, имя: 'Четвёртый', очки: 70, побед: 1, партий: 5 },
      { место: 5, имя: 'Пятый', очки: 60, побед: 1, партий: 5 }
    ],
    вокругМеня: [{ место: 2, имя: 'Я Игрок', очки: 90, побед: 3, партий: 5, этоЯ: true }]
  };
  const fetchУспех = function () {
    return Promise.resolve({ json: function () { return Promise.resolve(ответУспех); } });
  };

  /* ---- Сценарий А: мера «очки», пятеро лидеров, «я» — в тройке ---- */
  const поднятыйА = бр.поднять(исходник, { имяФайла: 'js/рейтинг-экран.js', fetch: fetchУспех });
  if (!поднятыйА.окно.ЭкранРейтинга || typeof поднятыйА.окно.ЭкранРейтинга.открыть !== 'function') {
    проверить('DOM: window.ЭкранРейтинга.открыть доступен после загрузки файла', false);
  } else {
    поднятыйА.окно.ЭкранРейтинга.открыть('дурак');
    await ждатьТик();
    /* Мера «сила» открыта по умолчанию — переключаемся на «очки»
       той же кнопкой, что нажал бы игрок на реальном экране. */
    const кнопкаОчки = поднятыйА.документ.getElementById('кнопка-рейтинг-очки');
    проверить('DOM: кнопка «Очки за победы» нашлась на построенном экране', Boolean(кнопкаОчки));
    if (кнопкаОчки) кнопкаОчки.click();

    const таблица = поднятыйА.документ.getElementById('рейтинг-таблица');
    проверить('DOM: узел #рейтинг-таблица нашёлся', Boolean(таблица));

    if (таблица) {
      const дети = таблица.children;
      const первыйУзел = дети[0] || null;
      проверить('DOM: первый узел в #рейтинг-таблица — .рейтинг-подиум',
        Boolean(первыйУзел) && первыйУзел.classList.contains('рейтинг-подиум'));

      const карточки = таблица.querySelectorAll('.рейтинг-подиум-карточка');
      проверить('DOM: внутри подиума ровно три узла .рейтинг-подиум-карточка',
        карточки.length === 3);

      const местаПоDOM = Array.prototype.map.call(карточки, function (к) {
        return к.getAttribute('data-место');
      }).join(',');
      проверить('DOM: порядок мест на подиуме по разметке — 2,1,3', местаПоDOM === '2,1,3');

      let именаИОчкиЕсть = карточки.length > 0;
      let своихКарточек = 0;
      for (let и = 0; и < карточки.length; и++) {
        const карточка = карточки[и];
        const имя = карточка.querySelector('.рейтинг-подиум-имя');
        const очки = карточка.querySelector('.рейтинг-подиум-очки');
        if (!имя || !имя.textContent || !имя.textContent.trim()) именаИОчкиЕсть = false;
        if (!очки || !очки.textContent || !очки.textContent.trim()) именаИОчкиЕсть = false;
        if (карточка.classList.contains('рейтинг-подиум-карточка--я')) своихКарточек += 1;
      }
      проверить('DOM: у каждой карточки подиума есть непустое имя и непустые очки',
        именаИОчкиЕсть);
      проверить('DOM: карточка «я» (место 2, входит в тройку) помечена классом --я ровно один раз',
        своихКарточек === 1);

      const строки = таблица.querySelectorAll('.рейтинг-строка');
      проверить('DOM: под подиумом есть хотя бы одна обычная строка списка', строки.length > 0);
      проверить('DOM: список под подиумом начинается со строки места 4',
        строки.length > 0 && строки[0].getAttribute('data-место') === '4');
    }

    проверить('DOM: ни одной ошибки в консоли (сценарий «мера очки», подиум полный)',
      поднятыйА.ошибкиКонсоли.length === 0);
  }

  /* ---- Сценарий Б: мера «сила» — подиума в таблице быть не должно ---- */
  const поднятыйБ = бр.поднять(исходник, { имяФайла: 'js/рейтинг-экран.js', fetch: fetchУспех });
  поднятыйБ.окно.ЭкранРейтинга.открыть('дурак');
  await ждатьТик();
  const таблицаБ = поднятыйБ.документ.getElementById('рейтинг-таблица');
  проверить('DOM: узел #рейтинг-таблица нашёлся (мера «сила»)', Boolean(таблицаБ));
  if (таблицаБ) {
    проверить('DOM: при мере «сила» узла .рейтинг-подиум в таблице нет',
      !таблицаБ.querySelector('.рейтинг-подиум'));
  }
  проверить('DOM: ни одной ошибки в консоли (сценарий «мера сила»)',
    поднятыйБ.ошибкиКонсоли.length === 0);

  /* ---- Сценарий В: беда связи — подиума в таблице тоже быть не должно ---- */
  const fetchБеда = function () { return Promise.reject(new Error('поддельная беда связи для проверки')); };
  const поднятыйВ = бр.поднять(исходник, { имяФайла: 'js/рейтинг-экран.js', fetch: fetchБеда });
  поднятыйВ.окно.ЭкранРейтинга.открыть('дурак');
  await ждатьТик();
  const кнопкаОчкиВ = поднятыйВ.документ.getElementById('кнопка-рейтинг-очки');
  if (кнопкаОчкиВ) кнопкаОчкиВ.click();
  const таблицаВ = поднятыйВ.документ.getElementById('рейтинг-таблица');
  проверить('DOM: узел #рейтинг-таблица нашёлся (беда связи)', Boolean(таблицаВ));
  if (таблицаВ) {
    проверить('DOM: при беде связи узла .рейтинг-подиум в таблице нет',
      !таблицаВ.querySelector('.рейтинг-подиум'));
  }
  проверить('DOM: ни одной ошибки в консоли (сценарий «беда связи»)',
    поднятыйВ.ошибкиКонсоли.length === 0);
}

/**
 * Прогнать обе части проверки (чистые функции + DOM) по одному файлу.
 * Возвращает число провалов. Используется и в чистом прогоне, и
 * в ломающем — на копии гоняются ровно те же проверки, без исключений.
 */
async function прогнать(путьМодуля) {
  let всего = 0;
  let провалов = 0;
  function проверить(имя, условие) {
    всего += 1;
    if (!условие) {
      провалов += 1;
      console.log('НЕ ПРОШЛО: ' + имя);
    }
  }

  const путьПолный = path.resolve(путьМодуля);

  let модуль = null;
  try {
    delete require.cache[путьПолный];
    модуль = require(путьПолный);
  } catch (сбой) {
    console.log('УПАЛО: require(«' + путьМодуля + '») сломался: ' + сбой.message);
  }
  if (модуль) {
    проверитьЧистыеФункции(модуль, проверить);
  } else {
    проверить('модуль вообще загрузился в Node (require не упал)', false);
  }

  let исходник = null;
  try {
    исходник = fs.readFileSync(путьПолный, 'utf8');
  } catch (сбой) {
    console.log('УПАЛО: не удалось прочитать файл «' + путьМодуля + '»: ' + сбой.message);
  }
  if (исходник) {
    try {
      await проверитьDOM(исходник, проверить);
    } catch (сбой) {
      console.log('УПАЛО: DOM-проверки подиума упали целиком: ' + (сбой && сбой.stack ? сбой.stack : сбой));
      всего += 1;
      провалов += 1;
    }
  } else {
    проверить('исходник файла прочитан для DOM-проверок', false);
  }

  console.log('');
  console.log('Итого проверок: ' + всего + ', провалов: ' + провалов);
  return провалов;
}

async function главная() {
  const индексФлага = process.argv.indexOf('--сломать');
  const ломающий = индексФлага !== -1;
  let путь = ПУТЬ_ПО_УМОЛЧАНИЮ;

  if (ломающий) {
    путь = process.argv[индексФлага + 1];
    if (!путь) {
      console.log('ОШИБКА: флаг --сломать требует путь к испорченной копии js/рейтинг-экран.js');
      console.log('Пример: node tests/подиум-2-1-3.js --сломать C:\\путь\\к\\копии\\рейтинг-экран.js');
      process.exit(1);
      return;
    }
    if (!fs.existsSync(путь)) {
      console.log('ОШИБКА: файл копии не найден: ' + путь);
      process.exit(1);
      return;
    }
    console.log('Ломающий запуск: гоняю те же проверки по копии ' + путь);
    console.log('');
  }

  const провалов = await прогнать(путь);

  if (ломающий) {
    console.log('');
    if (провалов === 0) {
      console.log('ПРОВЕРКА СЛЕПАЯ: на испорченной копии ни одна проверка не покраснела!');
      console.log('Это значит, что проверка не ловит настоящую поломку — её саму надо чинить.');
    } else {
      console.log('Ломающий запуск покраснел, как и должен: провалов ' + провалов + '.');
    }
    /* Ломающий запуск обязан завершиться кодом 1 в любом случае: либо
       потому что честно поймал поломку (это и есть цель запуска), либо
       потому что не поймал — а это уже повод чинить саму проверку. */
    process.exit(1);
    return;
  }

  process.exit(провалов > 0 ? 1 : 0);
}

главная().catch(function (сбой) {
  console.log('УПАЛО: главная() проверки подиума рухнула: ' + (сбой && сбой.stack ? сбой.stack : сбой));
  process.exit(1);
});
