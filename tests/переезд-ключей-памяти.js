/* =====================================================================
   ПЕРЕЕЗД КЛЮЧЕЙ ПАМЯТИ: старое имя → новое, не потеряв выбор человека.

   Зачем. Имена ключей сведены к латинице: облако Telegram ключ с русскими
   буквами не принимает вовсе, а разнобой имён однажды сбил проверяющего —
   он искал русское имя, не нашёл и решил, что настройка не сохраняется.
   В тот раз тревога была ложной, в следующий может оказаться настоящей.

   Чем это опасно для игрока. Переименование ключа СТИРАЕТ настройку: игра
   идёт искать новое имя, не находит и решает, что человек ничего не
   выбирал. Звук снова включается, метки на доске возвращаются, серия
   побед обнуляется. Поэтому переименование всегда идёт парой с переносом,
   и эта проверка показывает перенос на деле: кладём значение под старым
   именем, поднимаем файл — выбор на месте под новым.

   Запуск: node tests/переезд-ключей-памяти.js
   Выход 0 — провалов нет.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const КОРЕНЬ = path.join(__dirname, '..');

let проверок = 0;
const провалы = [];
function проверить(условие, что) {
  проверок++;
  if (!условие) { провалы.push(что); console.log('  ПРОВАЛ: ' + что); }
  else console.log('  ок   ' + что);
}

/** Поддельная память браузера: помнит, что в неё клали. */
function память(начальное) {
  const ящик = Object.assign({}, начальное || {});
  return {
    ящик: ящик,
    getItem: к => (к in ящик ? ящик[к] : null),
    setItem: (к, з) => { ящик[к] = String(з); },
    removeItem: к => { delete ящик[к]; }
  };
}

/**
 * Поднять файл игры в песочнице с поддельным браузером.
 * Возвращает окно — из него видно и window.ШашкиЗвук, и саму память.
 */
function поднять(файл, начальнаяПамять) {
  const исходник = fs.readFileSync(path.join(КОРЕНЬ, файл), 'utf8');
  const хранилище = память(начальнаяПамять);
  const узел = () => ({
    classList: { add() {}, remove() {}, toggle() {}, contains: () => false },
    addEventListener() {}, setAttribute() {}, appendChild() {},
    querySelector: () => null, querySelectorAll: () => [],
    style: { setProperty() {}, removeProperty() {}, getPropertyValue: () => '' },
    insertBefore() {}, removeChild() {}, remove() {}, contains: () => false,
    getBoundingClientRect: () => ({ top: 0, left: 0, width: 0, height: 0, bottom: 0, right: 0 }),
    focus() {}, blur() {}, click() {},
    textContent: '', className: '', id: '', value: '', disabled: false,
    dataset: {}, children: [], firstChild: null, parentNode: null
  });
  /* Экран шашек без правил уходит с первой же строки («правила не
     загрузились»), а телеграмный файл ждёт объект Telegram. Подкладываем
     обоим самое необходимое — иначе проверка мерила бы не перенос ключей,
     а собственную бедность. */
  const окно = {
    ШашкиПравила: {
      БЕЛЫЕ: 'белые', ЧЁРНЫЕ: 'чёрные', ПОЛЯ: [],
      создатьПартию: () => ({ доска: [], ходит: 'белые' }),
      картинкаПартии: () => [], партияИзКартинки: () => ({}),
      возможныеХоды: () => [], естьБой: () => false, чейХод: () => 'белые',
      партияЗавершена: () => false, итог: () => null, фишка: () => null,
      сколькоФишек: () => ({ всего: 0 }), найтиХод: () => null, сделатьХод: () => false
    },
    ШашкиЗнаки: { ЭМОЦИИ: [], ФРАЗЫ: [], БРОСКИ: [], сколькоЗнаков: () => 0,
      этоЗнак: () => false, этоБросок: () => false, знакПоНомеру: () => '',
      первыйНомерБроска: () => 1, ответНаЗнак: () => null },
    Telegram: { WebApp: { ready() {}, expand() {}, onEvent() {}, offEvent() {},
      initDataUnsafe: {}, themeParams: {}, isVersionAtLeast: () => false,
      CloudStorage: null, HapticFeedback: null, version: '6.0', platform: 'unknown' } },
    localStorage: хранилище,
    addEventListener() {}, removeEventListener() {},
    matchMedia: () => ({ matches: false, addEventListener() {}, addListener() {} }),
    setTimeout, clearTimeout, setInterval, clearInterval
  };
  const документ = {
    getElementById: () => null,
    querySelector: () => null,
    querySelectorAll: () => [],
    createElement: узел,
    addEventListener() {},
    documentElement: узел(),
    head: узел(),
    body: узел()
  };
  const песочница = {
    window: окно, document: документ, localStorage: хранилище,
    console: { log() {}, warn() {}, error() {} },
    setTimeout, clearTimeout, setInterval, clearInterval,
    Math, JSON, Date, Number, String, Array, Object, Boolean, RegExp, Error
  };
  песочница.globalThis = песочница;
  vm.createContext(песочница);
  try {
    vm.runInContext(исходник, песочница, { filename: файл });
  } catch (сбой) {
    console.log('   (файл упал в песочнице: ' + сбой.message + ')');
  }
  return { окно: окно, память: хранилище };
}

console.log('=== Переезд ключей памяти ===\n');

/* ---- Звук в шашках: выключен под старым именем ---- */
console.log('1. Звук шашек: выключенный вчера остаётся выключенным');
const звук = поднять('js/шашки-звук.js', { 'шашки:звук': 'выключен' });
проверить(звук.память.getItem('shashki_sound') === 'выключен',
  'значение переехало под латинское имя');
проверить(звук.окно.ШашкиЗвук && звук.окно.ШашкиЗвук.включён() === false,
  'игра видит выбор человека: звук выключен');
проверить(звук.память.getItem('шашки:звук') === 'выключен',
  'старое имя не стёрто — старая страница на другом устройстве ещё работает');

/* ---- Уже выбрано под новым именем: старое не должно перебивать ---- */
console.log('\n2. Новое имя сильнее старого');
const спор = поднять('js/шашки-звук.js', { 'шашки:звук': 'выключен', 'shashki_sound': 'включен' });
проверить(спор.память.getItem('shashki_sound') === 'включен',
  'свежий выбор не затирается вчерашним');

/* ---- Метки на доске ---- */
console.log('\n3. Метки на доске');
const метки = поднять('js/шашки-экран.js', { 'шашки:метки': 'нет' });
проверить(метки.память.getItem('shashki_marks') === 'нет',
  'выбор «без меток» переехал под новое имя');

/* ---- Серия побед ---- */
console.log('\n4. Серия побед в шашках');
const серия = поднять('js/шашки-рекорды.js', { 'шашки:серия': '7' });
проверить(серия.память.getItem('shashki_streak') === '7',
  'серия из семи побед не потерялась при переезде');

/* ---- И сама общая дверь ---- */
console.log('\n5. Общая дверь переноса');
const телеграм = поднять('js/telegram.js', { 'старое_имя': 'значение' });
const дверь = телеграм.окно.Телеграм && телеграм.окно.Телеграм.перенестиНастройку;
проверить(typeof дверь === 'function', 'дверь window.Телеграм.перенестиНастройку есть');
if (typeof дверь === 'function') {
  проверить(дверь('старое_имя', 'новое_имя') === true, 'перенос отвечает «да», когда перенёс');
  проверить(телеграм.память.getItem('новое_имя') === 'значение', 'значение и правда переехало');
  проверить(дверь('старое_имя', 'новое_имя') === false,
    'второй раз не переносит: под новым именем уже есть');
  проверить(дверь('пусто_тут', 'куда_то') === false, 'нечего переносить — говорит «нет»');
}

console.log('\n----------------------------------------');
console.log('Проверок сделано: ' + проверок);
console.log('ПРОВАЛОВ: ' + провалы.length);
process.exit(провалы.length === 0 ? 0 : 1);
