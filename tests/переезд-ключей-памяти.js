for (const [старое, новое, значение, что] of переезды) {
  проверить(дурак.память.getItem(новое) === значение, что + ' переехал под «' + новое + '»');
  проверить(дурак.память.getItem(старое) === значение, что + ': старое имя не стёрто');
}

/* ---- Сеть: адрес сервера и всё, что вокруг него ----

   Адрес сервера — самый дорогой из ключей: без него не создать игру
   с другом, и эту беду мы уже чинили. Читают его два файла, поэтому
   проверяем оба. */
console.log('\n7. Сеть: адрес сервера, комната, знакомые, вкладка');
const сеть = поднять('js/сеть.js', {
  'подкидной-дурак:адрес-сервера': 'https://вчерашний.example',
  'подкидной-дурак:комната': '{"код":"ABCD"}',
  'подкидной-дурак:знакомые': '["Друг"]',
  'подкидной-дурак:вкладка': 'вкладка-1'
});
проверить(сеть.память.getItem('server_address') === 'https://вчерашний.example',
  'адрес сервера переехал — игра с другом создастся');
проверить(сеть.память.getItem('room_durak') === '{"код":"ABCD"}',
  'начатая партия не потерялась: комната переехала');
проверить(сеть.память.getItem('friends') === '["Друг"]', 'список знакомых переехал');
проверить(сеть.память.getItem('tab_name') === 'вкладка-1', 'имя вкладки переехало');
проверить(сеть.память.getItem('подкидной-дурак:адрес-сервера') === 'https://вчерашний.example',
  'старое имя адреса не стёрто');

/* «Похвастаться» читает адрес сам. Он должен видеть и новое имя,
   и старое: страница может открыться вовсе без js/сеть.js. */
console.log('\n8. «Похвастаться» находит адрес под обоими именами');
for (const имя of ['server_address', 'подкидной-дурак:адрес-сервера']) {
  const хвастовство = поднять('js/похвастаться.js', { [имя]: 'https://адрес.example' });
  const исходник = fs.readFileSync(path.join(КОРЕНЬ, 'js/похвастаться.js'), 'utf8');
  проверить(исходник.indexOf(имя) !== -1, 'знает про имя «' + имя + '»');
  void хвастовство;
}

