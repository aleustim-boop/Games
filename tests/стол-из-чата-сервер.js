/* ---------------------------------------------------------------------
   Разговор с сервером — так же, как его ведёт бот (запросКСерверу
   в bot/бот.js): тела нет — GET, ответ — { ок, номер, данные } или null.
   --------------------------------------------------------------------- */
function запросКСерверу(адрес, путь, тело) {
  return new Promise(function (готово) {
    const куда = new URL(String(адрес).replace(/\/+$/, '') + путь);
    const данные = тело === undefined ? null : Buffer.from(JSON.stringify(тело), 'utf8');
    const заголовки = {};
    if (данные) {
      заголовки['Content-Type'] = 'application/json';
      заголовки['Content-Length'] = данные.length;
    }
    const запрос = http.request({
      hostname: куда.hostname, port: куда.port, path: куда.pathname + куда.search,
      method: данные ? 'POST' : 'GET', headers: заголовки
    }, function (ответ) {
      let текст = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (сбой) { разобрано = null; }
        готово({ ок: ответ.statusCode >= 200 && ответ.statusCode < 300, номер: ответ.statusCode, данные: разобрано || {} });
      });
    });
    запрос.on('error', function () { готово(null); });
    if (данные) запрос.write(данные);
    запрос.end();
  });
}

