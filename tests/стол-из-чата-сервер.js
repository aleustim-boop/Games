async function проверитьИгры() {
  const стол = собратьМодуль(сервера.пропускБотаИзТокена(ТОКЕН_ДЛЯ_ПРОБЫ));
  const игры = Названия.сетевыеИгры();
  проверить(игры.length === 11, 'в таблице названий 11 игр по сети (' + игры.length + ')');

  let человек = 9400100;
  for (const игра of игры) {
    const слова = Названия.словаИгры(игра);
    console.log('Игра: ' + игра);
    const отметка = сказано.length;
    const открыт = await стол.позватьКСтолу(команда(++человек, -1009400000 - человек), игра);
    const письмо = сказаноПосле(отметка, 'sendMessage')[0];
    const кнопка = письмо && письмо.данные.reply_markup ? письмо.данные.reply_markup.inline_keyboard[0][0] : null;
    проверить(открыт === true && Boolean(кнопка && кнопка.url),
      игра + ': сервер признал пропуск, приглашение с кнопкой ушло в чат');
    if (!кнопка || !кнопка.url) continue;

    const ссылка = разобратьСсылку(кнопка.url);
    проверить(ссылка.метка === (игра === 'дурак' ? '' : слова.метка) && ссылка.адрес === АДРЕС_СЕРВЕРА,
      игра + ': в ссылке метка «' + ссылка.метка + '» и адрес сервера');
    проверить(письмо.данные.text.indexOf('Саша зовёт за стол ' + слова.вИгру + '!') === 0,
      игра + ': приглашение зовёт «' + слова.вИгру + '»');

    const сведения = await запросКСерверу(АДРЕС_СЕРВЕРА, '/стол?код=' + encodeURIComponent(ссылка.код));
    const что = (сведения && сведения.данные) || {};
    проверить(что.есть === true && что.игра === игра,
      игра + ': дверь /стол говорит ту же игру (сказала «' + что.игра + '»)');
    проверить(что.людей === 0 && что.этап === 'ожидание',
      игра + ': стол пуст и ждёт — бот за него не сел (людей ' + что.людей + ', этап ' + что.этап + ')');
    проверить(письмо.данные.text.indexOf('Стол ждёт ' + СтолИзЧата.словамиМинут(Math.round(что.ждётЕщёСекунд / 60)) + '.') !== -1,
      игра + ': срок в приглашении — тот, что называет сервер');

    const первый = await запросКСерверу(АДРЕС_СЕРВЕРА, '/войти', { код: ссылка.код, имя: 'Первый' });
    const второй = await запросКСерверу(АДРЕС_СЕРВЕРА, '/войти', { код: ссылка.код, имя: 'Второй' });
    проверить(Boolean(первый && первый.ок && второй && второй.ок), игра + ': двое вошли по коду из ссылки');
    const яПервый = яЗаСтолом(первый);
    const яВторой = яЗаСтолом(второй);
    проверить(Boolean(яПервый) && яПервый.хозяин === true, игра + ': первый севший — хозяин стола');
    проверить(Boolean(яВторой) && яВторой.хозяин === false, игра + ': второй — не хозяин');

    const после = await запросКСерверу(АДРЕС_СЕРВЕРА, '/стол?код=' + encodeURIComponent(ссылка.код));
    проверить(Boolean(после && после.данные && после.данные.есть === true && после.данные.людей === 2),
      игра + ': дверь /стол видит двоих за столом');
  }

  await дождатьсяСторожей(стол);
  проверить(стол.открытыхСтолов() === 0, 'сторожа отпустили все столы, за которые сели');
  проверить(сказано.filter(function (з) { return з.метод === 'editMessageText'; }).length === 0,
    'ни одно приглашение живого стола не исправлено на «стол закрылся»');
}

