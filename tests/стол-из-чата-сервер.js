/** Хвост ссылки так, как его читает игра: «[метка_]КОД-адрес». */
function разобратьСсылку(ссылка) {
  let хвост = new URL(ссылка).searchParams.get('startapp') || '';
  let метка = '';
  const сМеткой = /^([a-z]+)_(.*)$/.exec(хвост);
  if (сМеткой) { метка = сМеткой[1]; хвост = сМеткой[2]; }
  const граница = хвост.indexOf('-');
  let буквы = хвост.slice(граница + 1).replace(/-/g, '+').replace(/_/g, '/');
  while (буквы.length % 4 !== 0) буквы += '=';
  return { метка: метка, код: хвост.slice(0, граница), адрес: Buffer.from(буквы, 'base64').toString('utf8') };
}

async function дождатьсяСторожей(стол) {
  for (let раз = 0; раз < 500 && стол.открытыхСтолов() > 0; раз++) await пауза(20);
}

/** Кто я за столом — из ответа сервера на «войти». */
function яЗаСтолом(ответ) {
  const состояние = (ответ && ответ.данные && ответ.данные.состояние) || {};
  const застолом = Array.isArray(состояние.застолом) ? состояние.застолом : [];
  return застолом.find(function (м) { return м && м.этоЯ; }) || null;
}

function портСвободен(порт) {
  return new Promise(function (готово) {
    const проба = net.createServer();
    проба.once('error', function () { готово(false); });
    проба.once('listening', function () { проба.close(function () { готово(true); }); });
    проба.listen(порт, ХОСТ);
  });
}

