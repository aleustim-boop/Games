async function проверитьЗакрытыйСтол() {
  console.log('Стола нет');
  /* Как сторож узнаёт, что стол закрылся: дверь /стол отвечает «есть: false».
     Сам путь «никто не сел → в чате Стол закрылся» проверен в
     bot/проверка-стола.js на поддельных часах: настоящий сервер держит
     пустой стол пять минут, и ждать их здесь незачем. Тут сверяем только,
     что настоящий сервер отвечает про несуществующий стол тем самым видом,
     на который сторож опирается. */
  const сведения = await запросКСерверу(АДРЕС_СЕРВЕРА, '/стол?код=' + encodeURIComponent('ZZZZ'));
  проверить(Boolean(сведения && сведения.ок && сведения.данные && сведения.данные.есть === false),
    'про стол, которого нет, дверь /стол отвечает 200 и «есть: false» (' + JSON.stringify(сведения && сведения.данные) + ')');
}

