/** Старая игра из git — во временный файл системы, в проекте ничего не остаётся. */
function достатьСтаруюИгру() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'броски-старая-'));
  const файл = path.join(папка, 'старый-game.js');
  fs.writeFileSync(файл, execFileSync('git', ['show', КОММИТ_СТАРОЙ + ':js/game.js'], { cwd: КОРЕНЬ, maxBuffer: 64 * 1024 * 1024 }));
  return require(файл);
}

