/** Копия модуля с порчей; пути require — на настоящую папку server. */
function сделатьПорченую(имя) {
  const порча = ПОРЧИ[имя];
  let текст = fs.readFileSync(НАСТОЯЩИЙ_МОДУЛЬ, 'utf8');
  const мест = текст.split(порча.найти).length - 1;
  if (мест !== 1) throw new Error('Порча «' + имя + '»: нужное место найдено ' + мест + ' раз (ждали 1) — модуль изменился, обнови проверку.');
  текст = текст.replace(порча.найти, function () { return порча.заменить; });
  текст = текст.split("require('./").join("require('" + СЕРВЕР.split('\\').join('/') + '/');
  const папка = fs.mkdtempSync(path.join(ВРЕМЕННАЯ, 'копия-'));
  const файл = path.join(папка, 'турнир-письма.js');
  fs.writeFileSync(файл, текст, 'utf8');
  return файл;
}

function тик() {
  return new Promise(function (ок) { setImmediate(ок); });
}

/* ---------------------------------------------------------------------
   Прогон по одному модулю: возвращает { всего, провалы: [строки] }
   --------------------------------------------------------------------- */
async function прогон(путьМодуля) {
  let всего = 0;
  const провалы = [];
  function ждём(условие, что) {
    всего++;
    if (!условие) провалы.push(что);
  }

  /* Всё, что модуль скажет через console.error, копим: проверка тихая. */
  const прежнийError = console.error;
  const сказано = [];
  console.error = function (текст) { сказано.push(String(текст)); };
  try {
    await прогонВнутри(путьМодуля, ждём, сказано);
  } finally {
    console.error = прежнийError;
  }
  return { всего: всего, провалы: провалы };
}

