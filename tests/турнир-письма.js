  ждём(напоминания.every(function (п) { return /Турнир по дураку начнётся через 10 мин\./.test(п.текст); }), 'в тексте нет «Турнир по дураку начнётся через 10 мин.»: ' + (напоминания[0] && напоминания[0].текст));
