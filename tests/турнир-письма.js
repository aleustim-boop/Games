function печатьПровалов(результат) {
  результат.провалы.forEach(function (с) { console.log('  ПРОВАЛ: ' + с); });
}

/** Тот же прогон дочерним процессом в чужом поясе машины. */
function прогнатьВПоясе(пояс) {
  const итог = spawnSync(process.execPath, [__filename, '--внутри'], {
    env: Object.assign({}, process.env, { TZ: пояс }),
    encoding: 'utf8'
  });
  const строки = (итог.stdout || '').split('\n');
  const пояснённая = строки.filter(function (с) { return с.indexOf('СМЕЩЕНИЕ ') === 0; }).pop();
  return {
    код: итог.status,
    смещение: пояснённая ? Number(пояснённая.slice('СМЕЩЕНИЕ '.length)) : null,
    вывод: итог.stdout || ''
  };
}

async function главное() {
  const аргумент = process.argv[2] || '';

  if (аргумент === '--внутри') {
    const итог = await прогон(НАСТОЯЩИЙ_МОДУЛЬ);
    печатьПровалов(итог);
    console.log('СМЕЩЕНИЕ ' + new Date(Date.UTC(2026, 9, 5, 12, 0)).getTimezoneOffset());
    console.log('Итого проверок: ' + итог.всего + ', провалов: ' + итог.провалы.length);
    process.exit(итог.провалы.length ? 1 : 0);
  }

  const сломатьИмя = аргумент.indexOf('--сломать-') === 0 ? аргумент.slice('--сломать-'.length) : '';
  if (сломатьИмя) {
    if (!ПОРЧИ[сломатьИмя]) { console.log('Нет такой порчи: ' + сломатьИмя); process.exit(2); }
    const итог = await прогон(сделатьПорченую(сломатьИмя));
    печатьПровалов(итог);
    console.log('Итого проверок: ' + итог.всего + ', провалов: ' + итог.провалы.length + ' (порча «' + сломатьИмя + '»: красное и нужно)');
    process.exit(итог.провалы.length ? 1 : 0);
  }

  const настоящий = await прогон(НАСТОЯЩИЙ_МОДУЛЬ);
  печатьПровалов(настоящий);
  let всего = настоящий.всего;
  let провалов = настоящий.провалы.length;

  /* Тот же прогон в Asia/Tokyo. Если пояс не поменялся — сверка пустышка: краснеем. */
  const вТокио = прогнатьВПоясе('Asia/Tokyo');
  всего += 2;
  if (вТокио.код !== 0) {
    провалов++;
    console.log('  ПРОВАЛ: прогон в поясе Asia/Tokyo упал:\n' + вТокио.вывод);
  }
  const своёСмещение = new Date(Date.UTC(2026, 9, 5, 12, 0)).getTimezoneOffset();
  if (вТокио.смещение === null || вТокио.смещение === своёСмещение) {
    провалов++;
    console.log('  ПРОВАЛ: пояс в дочернем прогоне не отличается (' + вТокио.смещение + ' и ' + своёСмещение + ') — проверка поясов ничего не доказывает');
  }
  console.log('Пояс Asia/Tokyo: ' + (вТокио.код === 0 ? 'зелёный' : 'КРАСНЫЙ'));

  for (const имя of Object.keys(ПОРЧИ)) {
    const итог = await прогон(сделатьПорченую(имя));
    const покраснела = итог.провалы.length > 0;
    console.log('Порча «' + имя + '»: ' + (покраснела ? 'покраснела (проваленных проверок: ' + итог.провалы.length + ') — хорошо' : 'НЕ ПОКРАСНЕЛА — беда'));
    всего++;
    if (!покраснела) провалов++;
  }

  console.log('Итого проверок: ' + всего + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
}

главное().catch(function (беда) {
  console.log('Проверка упала: ' + (беда && беда.stack || беда));
  process.exit(1);
});
