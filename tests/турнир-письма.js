  const сЗаписью = письма.письмаИтога(мск(12, 20, 45, 0));
  ждём(сЗаписью.length === 1 && сЗаписью[0].номер === ранний, 'по записанМс итог ждали одному раннему, вышло ' + сЗаписью.length);

