function копияСПоломкой(имяПоломки, что, чем) {
  const корниКопии = path.join(os.tmpdir(),
    'рейтинг-страница-2-копия-' + имяПоломки + '-' + process.pid);
  fs.rmSync(корниКопии, { recursive: true, force: true });
  fs.mkdirSync(корниКопии, { recursive: true });
  временныеПапки.push(корниКопии);

  const безДанных = function (источник) {
    return path.basename(источник) !== 'данные';
  };
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(корниКопии, 'server'),
    { recursive: true, filter: безДанных });
  fs.cpSync(path.join(КОРЕНЬ, 'js'), path.join(корниКопии, 'js'),
    { recursive: true });

  const файлРейтинга = path.join(корниКопии, 'server', 'рейтинг.js');
  const было = fs.readFileSync(файлРейтинга, 'utf8');
  const стало = было.replace(что, чем);
  if (стало === было) {
    console.log('ПРИЁМ ПОРЧИ УСТАРЕЛ: в server/рейтинг.js не найдена строка');
    console.log('  искали: ' + что);
    console.log('  Файл переписали — обновите ломающий запуск в этой проверке.');
    process.exit(1);
  }
  fs.writeFileSync(файлРейтинга, стало, 'utf8');
  return path.join(корниКопии, 'server');
}

