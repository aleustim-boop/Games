  let ожидаемые = [];
  let подпись = '';

  if (СЛОМАТЬ_С_НУЛЯ) { ожидаемые = [2, 3, 5]; подпись = 'A'; }
  else if (СЛОМАТЬ_ОТПЕЧАТОК) { ожидаемые = [5]; подпись = 'B'; }
  else if (СЛОМАТЬ_ПОТОЛОК) { ожидаемые = [4]; подпись = 'C'; }
  else if (СЛОМАТЬ_СОГЛАСОВАННОСТЬ) { ожидаемые = [14]; подпись = 'D'; }
