/* Браузер получает порченую КОПИЮ вместо настоящего файла (поломкаТекст = { экран, правила } или null). */
async function подменитьФайлы(страница, поломкаТекст) {
  if (!поломкаТекст) return;
  await перехватить(страница, /[/]js[/](деберц-экран|деберц-правила)[.]js/, (путь, _з, адрес) => {
    const тело = адрес.includes('деберц-правила') ? поломкаТекст.правила : поломкаТекст.экран;
    if (тело === undefined) путь.continue();
    else путь.fulfill({ status: 200, contentType: 'text/javascript; charset=utf-8', body: тело });
  });
}
