/* ---------- стенд ---------- */
function свободныйПорт() {
  return new Promise((готово, беда) => {
    const с = net.createServer();
    с.on('error', беда);
    с.listen(0, '127.0.0.1', () => { const порт = с.address().port; с.close(() => готово(порт)); });
  });
}
function запустить(аргументы, метка, ждатьСлово, env) {
  const дочерний = spawn(process.execPath, аргументы, { stdio: 'pipe', env: Object.assign({}, process.env, env || {}) });
  return new Promise((готово, беда) => {
    let вывод = '';
    const т = setTimeout(() => беда(new Error(метка + ' не поднялся за 8с: ' + вывод)), 8000);
    дочерний.stdout.on('data', д => { вывод += д.toString(); if (вывод.includes(ждатьСлово)) { clearTimeout(т); готово({ дочерний, вывод }); } });
    дочерний.on('error', е => { clearTimeout(т); беда(е); });
  });
}

