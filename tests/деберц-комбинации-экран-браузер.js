function найтиРаздачу(условие) {
  for (let зерно = 1; зерно < 400000; зерно++) {
    const партия = { id: 'проверка-' + зерно, зерно, уровень: 'обычный', цель: 301, режим: '2', правила: 6, ходы: [] };
    const начало = Память.открыть(носительС(партия)).игра;
    // Игрок первым выбирает козырь, значит и первым ходит после выбора.
    if (!начало || начало.фаза !== 'торговля' || начало.ход !== 0) continue;
    const с = { ...партия, ходы: [['торг', 0, начало.открытая.масть]] };
    const игра = Память.открыть(носительС(с)).игра;
    if (игра && игра.фаза === 'игра' && игра.ход === 0 && чужиеЦеликом(игра) && условие(игра)) return { партия: с, игра };
  }
  return null;
}

