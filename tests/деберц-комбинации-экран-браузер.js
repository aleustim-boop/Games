function равно(факт, ждали, описание) {
  всего++;
  if (JSON.stringify(факт) !== JSON.stringify(ждали)) {
    провалы.push(описание);
    console.log('  ПРОВАЛ: ' + описание + '\n    ждали: ' + JSON.stringify(ждали) + '\n    получили: ' + JSON.stringify(факт));
  }
}

