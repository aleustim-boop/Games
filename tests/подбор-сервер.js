'use strict';

/* =====================================================================
   ПОДБОР СОПЕРНИКА НА СЕРВЕРЕ: «Играть онлайн» без кода и выбора стола.

   Что проверяем. Три новые двери сервера (server/сервер.js, поверх
   server/подбор.js и посадитьБотаОтПодбора из server/комнаты.js):
     POST /подбор         — встать в очередь на соперника с такими же
       правилами (игра всегда «дурак», местВСтоле всегда 2);
     POST /подбор-новости — длинный опрос очереди тем же ключом ожидания;
     POST /подбор-отмена  — выйти из очереди.

   Сверяем:
     — двое с одинаковыми правилами сводятся в одну комнату: код у обоих
       совпадает, пропуска разные, партия начинается сама (стол не
       «компания» — кнопки «Начать» подбор не обещает), оба видят
       соперника за столом;
     — переводной и обычные правила — разные очереди, друг с другом не
       сводятся;
     — не дождавшись соперника (порог подменён коротким для проверки —
       подбор.подменитьПорогОжиданияДляПроверки, тот же процесс, что
       и у сервера, — модуль общий), одиночке подсаживают бота и партия
       тоже стартует сама;
     — после /подбор-отмена тот же ключОжидания у /подбор-новости честно
       отвечает «не найдено», а не путает с чужой записью;
     — выдуманный, никому не принадлежащий ключОжидания у /подбор-новости
       и /подбор-отмена — тоже честное «не найдено» / «не получилось».

   Настоящего Telegram здесь нет: сервер отдаёт наружу одну щель для
   проверок (оснасткаДляПроверки) — выдуманный токен и поддельная труба.
   Данные уведены в сторону переменной ДАННЫЕ_ИГРЫ, боевые знакомства на
   диске не трогаются. Боевой сервер 8790 не трогается тоже: проверка
   поднимает свою копию на своём порту.

   Запуск:
       node tests/подбор-сервер.js
       node tests/подбор-сервер.js 8817      (свой порт)

   Ломающий прогон (проверка обязана покраснеть):
       node tests/подбор-сервер.js --сломать
   «--сломать» подменяет то, что ВИДИТ сама проверка (не код сервера):
   ответ «встал в очередь» превращается в фальшивое «уже свели» с
   выдуманными кодом и пропуском, а ответ «свели по-настоящему» —
   в фальшивое «продолжайте ждать». Тогда обязаны провалиться сверки
   и совпадения кода комнаты у пары, и получения бота, и обоих отказов
   «не найдено» (они вместо честного отказа получат фальшивое «свели»).
   Ноль провалов при «--сломать» значит, что проверка спит.

   Выход 0 — провалов нет, 1 — есть.
   ===================================================================== */

const path = require('path');
const os = require('os');
const http = require('http');
const crypto = require('crypto');

/* Данные уводим ДО подключения сервера — там настоящие имена и номера
   живых людей, проверке там делать нечего. */
process.env.ДАННЫЕ_ИГРЫ = path.join(os.tmpdir(), 'подбор-сервер-' + process.pid);

const КОРЕНЬ = path.join(__dirname, '..');
const сервера = require(path.join(КОРЕНЬ, 'server', 'сервер.js'));
/* Тот же самый модуль, что require'ит server/сервер.js (один процесс —
   один кэш require) — иначе подменитьПорогОжиданияДляПроверки говорила
   бы с чужой, никому не нужной копией очереди. */
const подбор = require(path.join(КОРЕНЬ, 'server', 'подбор.js'));

const ПОРТ = Number(process.argv[2]) || 8817;
const ХОЗЯИН_АДРЕС = '127.0.0.1';

const ЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;
if (ЛОМАТЬ) {
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: ответы подбора подменяем фальшивыми — ' +
              'проверка обязана покраснеть ***');
}

/* Выдуманный токен: им подписываются пробные данные, с настоящим токеном
   бота он не имеет ничего общего. */
const ТОКЕН_ДЛЯ_ПРОБЫ = '1234567:VYDUMANNYY-TOKEN-DLYA-PROVERKI-podbora';

/* Игроки. Номера выдуманы, но выглядят как настоящие номера Telegram. */
const АНЯ = 301, БОРЯ = 302, ВИТЯ = 303, ГАЛЯ = 304, ДИМА = 305, ЕГОР = 306;

let проверок = 0;
const провалы = [];

function проверить(условие, что) {
  проверок++;
  if (!условие) {
    провалы.push(что);
    console.log('  ПРОВАЛ: ' + что);
  }
}

/* ---------------------------------------------------------------------
   Подпись Telegram — по тому же правилу, что у сервера
   --------------------------------------------------------------------- */

function подписать(поля, токен) {
  const строки = Object.keys(поля)
    .filter(function (к) { return к !== 'hash'; })
    .map(function (к) { return к + '=' + поля[к]; })
    .sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(токен).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}

/** initData так, как её присылает настоящая страница Telegram. */
function подписьИгрока(номер, имя) {
  const поля = {
    query_id: 'AAF' + номер,
    user: JSON.stringify({ id: номер, first_name: имя, username: 'igrok' + номер }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  const сподписью = Object.assign({}, поля, { hash: подписать(поля, ТОКЕН_ДЛЯ_ПРОБЫ) });
  return Object.keys(сподписью)
    .map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(сподписью[к]); })
    .join('&');
}

/* ---------------------------------------------------------------------
   Разговор с дверью
   --------------------------------------------------------------------- */

function спросить(путь, тело) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН_АДРЕС, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (сбой) { разобрано = null; }
        готово({ код: ответ.statusCode, тело: разобрано || {}, текст: текст });
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

/* ---------------------------------------------------------------------
   Порча для ломающего запуска

   Два вида подмены на все виды сверок:
     подставитьСведение — там, где по-настоящему должно быть «ждёт» или
       «не найдено», подсовываем фальшивое «уже свели» с выдуманными
       кодом и пропуском — сверки «это не свели», «не найдено» обязаны
       упасть, а следующий /состояние по фальшивому коду отвечает пустой
       комнатой, что тоже роняет всё, что от него зависит;
     подставитьОжидание — там, где по-настоящему должно быть «свели»,
       подсовываем фальшивое «продолжайте ждать» без кода и пропуска —
       сверки «пара сведена в одну комнату» и «получил бота» обязаны
       упасть тем же путём (код/пропуск неопределены, /состояние ничего
       не находит).
   --------------------------------------------------------------------- */

function подставитьСведение(ответ) {
  if (!ЛОМАТЬ) return ответ;
  return {
    код: 200,
    тело: { изменилось: true, статус: 'свели', код: 'ЛОМ-КОД', пропуск: 'ЛОМ-ПРОПУСК' },
    текст: ''
  };
}

function подставитьОжидание(ответ) {
  if (!ЛОМАТЬ) return ответ;
  return {
    код: 200,
    тело: { статус: 'ждёт', изменилось: false, ключОжидания: 'ломаный-ключ', доБота: Date.now() + 999999 },
    текст: ''
  };
}

/* ---------------------------------------------------------------------
   Сами проверки
   --------------------------------------------------------------------- */

async function проверитьВсё() {

  console.log('1. Одинаковые правила: подбор сводит пару в одну комнату сам');
  const ответАни = await спросить('/подбор', {
    initData: подписьИгрока(АНЯ, 'Аня'), переводной: false
  });
  проверить(ответАни.код === 200 && ответАни.тело.статус === 'ждёт' &&
    typeof ответАни.тело.ключОжидания === 'string' && ответАни.тело.ключОжидания.length > 10,
    'Аня встаёт в очередь первой и получает ключ ожидания');

  const ответБори = подставитьСведение(await спросить('/подбор', {
    initData: подписьИгрока(БОРЯ, 'Боря'), переводной: false
  }));
  проверить(ответБори.код === 200 && ответБори.тело.статус === 'свели' &&
    Boolean(ответБори.тело.код) && Boolean(ответБори.тело.пропуск),
    'Боря встаёт вторым с теми же правилами и сразу сведён с Аней');

  const новостиАни = подставитьОжидание(await спросить('/подбор-новости', {
    ключОжидания: ответАни.тело.ключОжидания
  }));
  проверить(новостиАни.код === 200 && новостиАни.тело.статус === 'свели' &&
    Boolean(новостиАни.тело.код) && Boolean(новостиАни.тело.пропуск),
    'Аня узнаёт о сведении длинным опросом /подбор-новости');

  проверить(новостиАни.тело.код === ответБори.тело.код,
    'обоим досталась ровно одна и та же комната (совпадающий код)');
  проверить(новостиАни.тело.пропуск !== ответБори.тело.пропуск,
    'пропуска у Ани и Бори за одним столом разные');

  const глазамиАни = await спросить('/состояние', {
    код: новостиАни.тело.код, пропуск: новостиАни.тело.пропуск
  });
  const глазамиБори = await спросить('/состояние', {
    код: ответБори.тело.код, пропуск: ответБори.тело.пропуск
  });
  проверить(Boolean(глазамиАни.тело.состояние) && глазамиАни.тело.состояние.соперникПришёл === true &&
    глазамиАни.тело.состояние.этап === 'игра',
    'Аня видит соперника за столом и партию, начатую без единой кнопки «Начать»');
  проверить(Boolean(глазамиБори.тело.состояние) && глазамиБори.тело.состояние.соперникПришёл === true &&
    глазамиБори.тело.состояние.этап === 'игра',
    'Боря видит то же самое своими глазами');

  console.log('2. Разные правила (переводной и обычные) друг с другом не сводятся');
  const ответВити = подставитьСведение(await спросить('/подбор', {
    initData: подписьИгрока(ВИТЯ, 'Витя'), переводной: true
  }));
  проверить(ответВити.код === 200 && ответВити.тело.статус === 'ждёт',
    'Витя (переводной) встаёт в свою очередь и ждёт — сводить некем');
  const ответГали = подставитьСведение(await спросить('/подбор', {
    initData: подписьИгрока(ГАЛЯ, 'Галя'), переводной: false
  }));
  проверить(ответГали.код === 200 && ответГали.тело.статус === 'ждёт',
    'Галя (обычные правила) встаёт в другую очередь — с Витей их не сводят');
  // Прибираем за собой, не дожидаясь бота (у обоих обычный, не укороченный порог).
  await спросить('/подбор-отмена', { ключОжидания: ответВити.тело.ключОжидания });
  await спросить('/подбор-отмена', { ключОжидания: ответГали.тело.ключОжидания });

  console.log('3. Отмена убирает из очереди — повторный опрос честно отвечает «не найдено»');
  const ответЕгора = await спросить('/подбор', {
    initData: подписьИгрока(ЕГОР, 'Егор'), переводной: false
  });
  проверить(ответЕгора.код === 200 && ответЕгора.тело.статус === 'ждёт',
    'Егор встаёт в очередь один (Аня и Боря уже разобраны, ждать некому)');
  const отмена = await спросить('/подбор-отмена', { ключОжидания: ответЕгора.тело.ключОжидания });
  проверить(отмена.код === 200 && отмена.тело.ок === true, 'отмена по своему ключу принимается');
  const новостиПослеОтмены = подставитьСведение(await спросить('/подбор-новости', {
    ключОжидания: ответЕгора.тело.ключОжидания
  }));
  проверить(новостиПослеОтмены.код === 200 && новостиПослеОтмены.тело.статус === 'не_найдено',
    'тем же ключом после отмены — честное «не найдено», а не чужая запись');

  console.log('4. Выдуманный ключОжидания ничего не путает');
  const поддельныйКлюч = crypto.randomBytes(24).toString('hex');
  const новостиПоддельные = подставитьСведение(await спросить('/подбор-новости', {
    ключОжидания: поддельныйКлюч
  }));
  проверить(новостиПоддельные.код === 200 && новостиПоддельные.тело.статус === 'не_найдено',
    'выдуманный ключ ожидания у /подбор-новости — честное «не найдено»');
  const отменаПоддельная = await спросить('/подбор-отмена', { ключОжидания: поддельныйКлюч });
  проверить(отменаПоддельная.код === 200 && отменаПоддельная.тело.ок === false,
    'выдуманный ключ ожидания у /подбор-отмена — честное «не получилось»');

  console.log('5. Не дождавшись соперника (порог подменён), одиночка получает бота');
  подбор.подменитьПорогОжиданияДляПроверки(300); // вместо обычных 20 секунд — только для этой проверки
  try {
    const ответДимы = await спросить('/подбор', {
      initData: подписьИгрока(ДИМА, 'Дима'), переводной: false
    });
    проверить(ответДимы.код === 200 && ответДимы.тело.статус === 'ждёт',
      'Дима встаёт в очередь один — соперника с такими же правилами нет');

    const новостиДимы = подставитьОжидание(await спросить('/подбор-новости', {
      ключОжидания: ответДимы.тело.ключОжидания
    }));
    проверить(новостиДимы.код === 200 && новостиДимы.тело.статус === 'свели' &&
      Boolean(новостиДимы.тело.код) && Boolean(новостиДимы.тело.пропуск),
      'порог истёк — Диме подсаживают бота и сразу отдают код с пропуском');

    const глазамиДимы = await спросить('/состояние', {
      код: новостиДимы.тело.код, пропуск: новостиДимы.тело.пропуск
    });
    проверить(Boolean(глазамиДимы.тело.состояние) && глазамиДимы.тело.состояние.соперникПришёл === true &&
      глазамиДимы.тело.состояние.этап === 'игра',
      'Дима видит подсаженного бота за столом и партию, начатую без кнопки «Начать»');
  } finally {
    подбор.подменитьПорогОжиданияДляПроверки(); // возвращаем обычные 20 секунд
  }
}

/* ---------------------------------------------------------------------
   Запуск
   --------------------------------------------------------------------- */

(async function () {
  console.log('=== Подбор соперника: очередь, пара, бот ===');
  console.log('свой сервер на http://' + ХОЗЯИН_АДРЕС + ':' + ПОРТ + ' (боевой 8790 не трогаем)');
  console.log('Telegram поддельный, токен выдуманный, данные в ' + process.env.ДАННЫЕ_ИГРЫ + '\n');

  /* Труба в Telegram здесь не нужна вовсе (эти двери писем не шлют), но
     без неё оснастка не примет и выдуманный токен — а он нужен, чтобы
     сервер узнавал наших игроков по подписи. */
  сервера.оснасткаДляПроверки(ТОКЕН_ДЛЯ_ПРОБЫ, function () { return { ok: true }; });

  const сервер = сервера.создатьСервер();
  await new Promise(function (готово, беда) {
    сервер.once('error', беда);
    сервер.listen(ПОРТ, ХОЗЯИН_АДРЕС, готово);
  });

  let сбой = null;
  try {
    await проверитьВсё();
  } catch (беда) {
    сбой = беда;
  }

  сервер.close();
  сервера.оснасткаДляПроверки();     // возвращаем настоящий токен
  подбор.подменитьПорогОжиданияДляПроверки(); // на случай, если проверка оборвалась в середине пункта 5

  console.log('\n----------------------------------------');
  if (сбой) {
    console.log('ПРОВЕРКА ОБОРВАЛАСЬ: ' + сбой.message);
    console.log(сбой.stack);
  }
  for (const беда of провалы) console.log('  - ' + беда);
  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалы.length);
  console.log('\nЧего этой проверкой не увидеть: экран «Ищем соперника» в браузере — ' +
              'он ещё не сделан (Э4), и настоящий Telegram — подпись здесь выдуманная.');

  process.exit(сбой || провалы.length > 0 ? 1 : 0);
})();
