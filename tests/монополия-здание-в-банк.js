  отметить(P.stock(g).houses === 1, 'Сценарий 6б: раскладка верна — в банке ровно 1 дом');
  P.action(g, 0, { type: 'build', id: 16 });
  P.action(g, 0, { type: 'pass' });
  P.action(g, 1, { type: 'bid', amount: 50, id: 6 });
  P.action(g, 2, { type: 'bid', amount: 100, id: 11 });
  отметить(g.auction.high === 2 && g.auction.bid === 100, 'Сценарий 6б: раскладка верна — лидер В со ставкой 100');
  P.action(g, 2, { type: 'surrender' });
  отметить(Boolean(найтиСобытие(g, 'auctionWin', { player: 1, id: 6, amount: 50 })), 'Сценарий 6б: здание получил живой второй (Б, id6, 50) — как при выбытии флагом');
