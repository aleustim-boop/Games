'use strict';

/* =====================================================================
   МОНОПОЛИЯ: НЕГОДНЫЙ ЛИДЕР АУКЦИОНА ЗА ЗДАНИЕ — ЗДАНИЕ ОСТАЁТСЯ В БАНКЕ.

   Решение владельца 30.09 08:28: «При негодном лидере — здание в банк».
   В банке остался последний дом; идёт аукцион за него. Пока торги
   шли, лидер (высшая ставка) испортил себе место: продал дом по
   соседству (нарушил «стройте равномерно»), потерял деньги под ставку.
   Раньше здание тогда уходило ВТОРОМУ по ставке. Теперь так нельзя:
     - ставка лидера не списывается;
     - второй по ставке здание не получает и денег не платит;
     - в журнале «место победителя больше не годится» (auctionVoid) и
       «здание осталось в банке» (auctionEmpty);
     - партия идёт дальше: очередь дел после аукциона отрабатывает
       (pump), игра возвращается в этап «manage», «конец хода» проходит.
   Контроль: если лидер место НЕ портил — он получает здание как раньше
   (проверка не должна краснеть от «всегда отдаём в банк»).

   Правила общие для браузера и сервера: проверяем сам файл
   js/монополия-правила.js (его же require'ит сервер).

   Запуск:
       node tests/монополия-здание-в-банк.js
       node tests/монополия-здание-в-банк.js --сломать
       node tests/монополия-здание-в-банк.js --сломать <путь-к-копии-правил>

   --сломать без пути — сам делает КОПИЮ правил (вместе с файлом данных)
   во временной папке и возвращает в ней старое поведение: здание при
   негодном лидере уходит следующему по ставке. Проверка на копии обязана
   покраснеть (выход 1). С путём — проверяет ту копию, что дали (рядом
   должен лежать монополия-данные.js). Файл проекта не трогается.
   Если приём порчи не находит место в правилах — ошибка, а не «зелёное».
   ===================================================================== */

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const КОРЕНЬ = path.join(__dirname, '..');
const ПРАВИЛА_ПРОЕКТА = path.join(КОРЕНЬ, 'js', 'монополия-правила.js');
const ДАННЫЕ_ПРОЕКТА = path.join(КОРЕНЬ, 'js', 'монополия-данные.js');

const АРГУМЕНТЫ = process.argv.slice(2);
const ЛОМАТЬ = АРГУМЕНТЫ.includes('--сломать');
const АРГ_ПУТЬ = АРГУМЕНТЫ.find((а) => !а.startsWith('--'));

/* Старое поведение: перебираем всех по убыванию ставки и отдаём здание
   первому, у кого место годится. Этот кусок и есть то, что вырезано. */
const НОВЫЙ_КУСОК = `    const leader = order[0];
    if (leader === undefined) return -1;
    if (buildingTargetOk(g, a, leader, bids[leader])) return leader;`;
const СТАРЫЙ_КУСОК = `    for (const p of order) if (buildingTargetOk(g, a, p, bids[p])) return p;
    const leader = order[0];
    if (leader === undefined) return -1;`;

function сделатьЛомающуюКопию() {
  const текст = fs.readFileSync(ПРАВИЛА_ПРОЕКТА, 'utf8').replace(/\r\n/g, '\n');
  const вхождений = текст.split(НОВЫЙ_КУСОК).length - 1;
  if (вхождений !== 1) {
    throw new Error('приём порчи устарел: ожидалось ровно одно вхождение нового куска buildingWinner, нашлось ' + вхождений);
  }
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'монополия-здание-в-банк-'));
  fs.copyFileSync(ДАННЫЕ_ПРОЕКТА, path.join(папка, 'монополия-данные.js'));
  const копия = path.join(папка, 'монополия-правила.js');
  fs.writeFileSync(копия, текст.replace(НОВЫЙ_КУСОК, СТАРЫЙ_КУСОК), 'utf8');
  return копия;
}

let ПУТЬ_ПРАВИЛ = ПРАВИЛА_ПРОЕКТА;
if (АРГ_ПУТЬ) ПУТЬ_ПРАВИЛ = path.resolve(АРГ_ПУТЬ);
else if (ЛОМАТЬ) ПУТЬ_ПРАВИЛ = сделатьЛомающуюКопию();
const P = require(ПУТЬ_ПРАВИЛ);

let проверок = 0;
let провалов = 0;
function отметить(условие, текст) {
  проверок++;
  console.log((условие ? 'ок — ' : 'ПЛОХО — ') + текст);
  if (!условие) провалов++;
  return условие;
}

const own = (g, p, ids, level = 0) =>
  ids.forEach((id) => Object.assign(g.properties[id], { owner: p, level }));
const найтиСобытие = (g, kind, доп = {}) =>
  g.events.find((e) => e.kind === kind && Object.keys(доп).every((к) => e[к] === доп[к]));

/* Стол: три игрока. А запускает аукцион, у Б и В — свои кварталы с
   одним домиком на клетке (каждый может достроить ещё один), в банке
   ровно один дом. Ровно как в соседней проверке аукциона за здание. */
function стол(seed) {
  const g = P.create(3, seed);
  g.turn = 0;
  g.phase = 'manage';
  g.queue = [];
  own(g, 0, [16, 18, 19], 0);
  own(g, 1, [6, 8, 9], 1);
  own(g, 2, [11, 13, 14], 1);
  [21, 23, 24, 26, 27, 29].forEach((id) => { g.properties[id].level = 4; });
  g.properties[37].level = 1;
  g.properties[39].level = 0;
  return g;
}

/* Запускает торги и ставит: Б — 50 на id6, В — 100 на id11 (лидер).
   Возвращает стол в момент, когда ставки сделаны, а Б ещё не спасовал. */
function торгиСоСтавками(seed) {
  const g = стол(seed);
  P.action(g, 0, { type: 'build', id: 16 }); // А запускает аукцион за последний дом
  P.action(g, 0, { type: 'pass' });
  P.action(g, 1, { type: 'bid', amount: 50, id: 6 });
  P.action(g, 2, { type: 'bid', amount: 100, id: 11 });
  return g;
}

console.log('Проверка: негодный лидер аукциона за здание — здание в банк (правила: ' + ПУТЬ_ПРАВИЛ + (ЛОМАТЬ || АРГ_ПУТЬ ? ', это копия' : ', это файл проекта') + ')\n');

/* Что должно быть, когда здание осталось в банке. Общая часть сценариев
   1 и 3: второй (Б) цел, победителя нет, событие «в банке» есть. */
function проверитьЗданиеВБанке(g, название, номерЛидера, местоЛидера) {
  отметить(
    Boolean(найтиСобытие(g, 'auctionVoid', { player: номерЛидера, id: местоЛидера })),
    название + ': в журнале «место победителя больше не годится» (auctionVoid, игрок ' + номерЛидера + ', id' + местоЛидера + ')',
  );
  отметить(Boolean(найтиСобытие(g, 'auctionEmpty')), название + ': в журнале «здание осталось в банке» (auctionEmpty)');
  отметить(!найтиСобытие(g, 'auctionWin'), название + ': победителя аукциона нет — здание никому не отдано');
  отметить(g.players[1].money === 1500, название + ': второй по ставке (Б) ничего не заплатил (' + g.players[1].money + ', ожидали 1500)');
  отметить(g.properties[6].level === 1, название + ': на месте второго по ставке здание НЕ построено (id6 уровень ' + g.properties[6].level + ', ожидали 1)');
  отметить(g.auction === null, название + ': аукцион закрыт (g.auction пуст)');
}

/* Партия не встала: живой этап, очередь пуста, who() и assert() не падают,
   «конец хода» проходит. */
function проверитьЧтоПартияИдёт(g, название) {
  let ошибка = null;
  try {
    P.who(g);
    P.assert(g);
    P.action(g, 0, { type: 'end' });
  } catch (e) {
    ошибка = e;
  }
  отметить(!ошибка, название + ': партия идёт дальше — who, assert и «конец хода» без ошибок' + (ошибка ? ' (упало: ' + ошибка.message + ')' : ''));
  отметить(g.turn === 1 && g.phase !== 'auction', название + ': после «конца хода» ход у Б, этап «' + g.phase + '» (turn=' + g.turn + ')');
}

/* --------------------------------------------------------------------
   СЦЕНАРИЙ 1. Лидер (В, 100) продаёт дом рядом — место id11 неровное.
   Б (50) место годное, но здание ему не достаётся. После аукциона в
   очереди ждёт платёж А банку на 10 — он обязан пройти (pump идёт).
-------------------------------------------------------------------- */
console.log('--- Сценарий 1: лидер продал дом рядом ---');
{
  const g = торгиСоСтавками(11);
  отметить(P.stock(g).houses === 1, 'Сценарий 1: в банке ровно 1 дом');
  g.queue.push({ kind: 'pay', from: 0, to: -1, amount: 10, reason: 'Платёж после аукциона' });
  P.action(g, 2, { type: 'sell', id: 13 });
  отметить(!P.buildable(g, 2, 11), 'Сценарий 1: раскладка верна — место лидера (id11) больше не годится');
  отметить(P.buildable(g, 1, 6), 'Сценарий 1: раскладка верна — место второго (id6) годится, и всё равно здание ему не положено');
  P.action(g, 1, { type: 'pass' }); // Б пасует — торги кончились
  проверитьЗданиеВБанке(g, 'Сценарий 1', 2, 11);
  // В получил только 50 за проданный дом (половина цены), ставка 100 не списана.
  отметить(g.players[2].money === 1550, 'Сценарий 1: у лидера ставка не списана, только выручка за проданный дом (' + g.players[2].money + ', ожидали 1550)');
  отметить(g.players[0].money === 1490, 'Сценарий 1: очередь после аукциона отработала — платёж А прошёл (' + g.players[0].money + ', ожидали 1490)');
  отметить(P.stock(g).houses === 2, 'Сценарий 1: проданный дом вернулся в банк, а последний не ушёл (' + P.stock(g).houses + ', ожидали 2)');
  проверитьЧтоПартияИдёт(g, 'Сценарий 1');
}

/* --------------------------------------------------------------------
   СЦЕНАРИЙ 2. Лидер потерял деньги: место ровное, но на ставку 100
   наличных уже нет. Тоже «негоден» — здание в банк, Б не платит.
-------------------------------------------------------------------- */
console.log('\n--- Сценарий 2: у лидера не хватает денег на ставку ---');
{
  const g = торгиСоСтавками(12);
  g.players[2].money = 60; // потратил деньги, пока шли торги
  отметить(P.buildable(g, 2, 11), 'Сценарий 2: раскладка верна — место лидера ровное, дело только в деньгах');
  P.action(g, 1, { type: 'pass' });
  проверитьЗданиеВБанке(g, 'Сценарий 2', 2, 11);
  отметить(g.players[2].money === 60, 'Сценарий 2: у лидера денег не убавилось (' + g.players[2].money + ', ожидали 60)');
  проверитьЧтоПартияИдёт(g, 'Сценарий 2');
}

/* --------------------------------------------------------------------
   СЦЕНАРИЙ 3. Контроль наоборот: место испортил не лидер, а Б (тот,
   кого перебили). Лидер В цел — здание достаётся ему. «В банк» — только
   при негодном ЛИДЕРЕ, чужие порчи ничего не отменяют.
-------------------------------------------------------------------- */
console.log('\n--- Сценарий 3: контроль — лидер цел, испортился только второй ---');
{
  const g = торгиСоСтавками(13);
  P.action(g, 1, { type: 'sell', id: 8 }); // Б портит своё место
  отметить(!P.buildable(g, 1, 6), 'Сценарий 3: раскладка верна — место второго (id6) больше не годится');
  P.action(g, 1, { type: 'pass' });
  отметить(Boolean(найтиСобытие(g, 'auctionWin', { player: 2, id: 11, amount: 100 })), 'Сценарий 3: лидер получил здание (auctionWin, В, id11, 100)');
  отметить(g.players[2].money === 1400, 'Сценарий 3: у лидера списана ставка 100 (' + g.players[2].money + ', ожидали 1400)');
  отметить(g.properties[11].level === 2, 'Сценарий 3: на месте лидера построен дом (id11 уровень ' + g.properties[11].level + ')');
  отметить(!найтиСобытие(g, 'auctionVoid'), 'Сценарий 3: отказов «место не годится» нет');
}

/* --------------------------------------------------------------------
   СЦЕНАРИЙ 4. Контроль без порчи: все места целы — лидер строит.
-------------------------------------------------------------------- */
console.log('\n--- Сценарий 4: контроль — всё цело, лидер строит ---');
{
  const g = торгиСоСтавками(14);
  P.action(g, 1, { type: 'pass' });
  отметить(Boolean(найтиСобытие(g, 'auctionWin', { player: 2, id: 11, amount: 100 })), 'Сценарий 4: лидер получил здание (auctionWin, В, id11, 100)');
  отметить(g.players[2].money === 1400 && g.properties[11].level === 2, 'Сценарий 4: ставка списана, дом стоит на id11');
  проверитьЧтоПартияИдёт(g, 'Сценарий 4');
}

console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);
if (провалов > 0) process.exit(1);
