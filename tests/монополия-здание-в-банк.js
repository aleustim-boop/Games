/* Поломки КОПИИ правил. У каждой: что портим (было -> стало) и что она
   имитирует. «Было» обязано встретиться в правилах РОВНО один раз, иначе
   это ошибка запуска (выход 2), а не тихий пропуск. */
const ПОЛОМКИ = [
  {
    название: 'здание отдаётся негодному лидеру, как до правки (уходит следующему по ставке)',
    было: `    const leader = order[0];
    if (leader === undefined) return -1;
    if (buildingTargetOk(g, a, leader, bids[leader])) return leader;`,
    стало: `    for (const p of order) if (buildingTargetOk(g, a, p, bids[p])) return p;
    const leader = order[0];
    if (leader === undefined) return -1;`,
  },
  {
    название: 'при выбывшем/негодном лидере аукцион не закрывается (партия зависает)',
    было: `    g.auction = null;
    g.queue.shift();
    pump(g);
  }
  function auctionNext(g) {`,
    стало: `    if (a.high >= 0) {
      g.auction = null;
      g.queue.shift();
      pump(g);
    }
  }
  function auctionNext(g) {`,
  },
  {
    // Ставку выбывшего снимает dropOutBids, фильтр в buildingWinner —
    // запасной. Портим оба места, иначе второе прикрыло бы первое.
    название: 'выбывшие не отбрасываются: здание может достаться вышедшему из игры',
    замены: [
      {
        было: `        .map(Number)
        .filter((i) => !g.players[i].out)
        .sort(`,
        стало: `        .map(Number)
        .sort(`,
      },
      {
        было: `      if (out(Number(k))) {
        delete a.bids[k];`,
        стало: `      if (false) {
        delete a.bids[k];`,
      },
    ],
  },
  {
    название: 'запасной путь без a.bids сломан: список ставок берётся как есть',
    было: `bids = (a.bids = a.bids || { [a.high]: a.bid }),`,
    стало: `bids = a.bids,`,
  },
];

function сделатьЛомающуюКопию(папкаКопии, номер) {
  const п = ПОЛОМКИ[номер - 1];
  if (!п) throw new Error('нет поломки с номером ' + номер + ' (есть 1..' + ПОЛОМКИ.length + ')');
  let текст = fs.readFileSync(ПРАВИЛА_ПРОЕКТА, 'utf8').replace(/\r\n/g, '\n');
  // Поломка — одна замена (было/стало) или несколько (замены); каждая
  // обязана найти свой кусок правил ровно один раз.
  for (const з of п.замены || [{ было: п.было, стало: п.стало }]) {
    const вхождений = текст.split(з.было).length - 1;
    if (вхождений !== 1) {
      throw new Error('приём порчи №' + номер + ' устарел: ожидалось ровно одно вхождение куска правил, нашлось ' + вхождений);
    }
    текст = текст.replace(з.было, () => з.стало);
  }
  const папка = path.resolve(папкаКопии);
  const относит = path.relative(КОРЕНЬ, папка);
  if (!относит.startsWith('..') && !path.isAbsolute(относит)) {
    throw new Error('копию нельзя класть внутрь проекта: ' + папка);
  }
  fs.mkdirSync(папка, { recursive: true });
  fs.copyFileSync(ДАННЫЕ_ПРОЕКТА, path.join(папка, 'монополия-данные.js'));
  const копия = path.join(папка, 'монополия-правила.js');
  fs.writeFileSync(копия, текст, 'utf8');
  return копия;
}

/* --сломать-все <папка>: гоняем каждую поломку отдельным запуском этого
   же файла; каждая обязана покраснеть (выход 1 и строки «ПЛОХО»). Обычный
   прогон на настоящих правилах обязан быть зелёным. */
if (ЛОМАТЬ_ВСЁ) {
  const { spawnSync } = require('node:child_process');
  if (!БЕЗ_ФЛАГОВ[0]) { console.error('нужна папка вне проекта: --сломать-все <папка>'); process.exit(2); }
  let изъянов = 0;
  const обычный = spawnSync(process.execPath, [__filename], { encoding: 'utf8' });
  console.log((обычный.status === 0 ? 'ок — ' : 'ПЛОХО — ') + 'обычный прогон на настоящих правилах зелёный (выход ' + обычный.status + ')');
  if (обычный.status !== 0) изъянов++;
  ПОЛОМКИ.forEach((п, i) => {
    const н = i + 1;
    const р = spawnSync(process.execPath, [__filename, '--сломать', path.join(БЕЗ_ФЛАГОВ[0], 'поломка-' + н), String(н)], { encoding: 'utf8' });
    const итог = ((р.stdout || '').match(/Итого проверок: (\d+), провалов: (\d+)/) || []);
    const покраснела = р.status === 1 && Number(итог[2]) > 0;
    console.log((покраснела ? 'ок — ' : 'ПЛОХО — ') + 'поломка ' + н + ' («' + п.название + '») ' + (покраснела ? 'покраснела: проверок ' + итог[1] + ', провалов ' + итог[2] : 'НЕ покраснела (выход ' + р.status + ') ' + (р.stderr || '').split('\n')[0]));
    if (!покраснела) изъянов++;
  });
  console.log('\nИтого поломок: ' + ПОЛОМКИ.length + ', не покраснели: ' + изъянов);
  process.exit(изъянов ? 1 : 0);
}

let ПУТЬ_ПРАВИЛ = ПРАВИЛА_ПРОЕКТА;
