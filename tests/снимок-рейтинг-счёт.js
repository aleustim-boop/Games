'use strict';

/* =====================================================================
   СНИМОК ЭКРАНА «РЕЙТИНГ 2048» (таблица лучшего счёта, этап Э4.5).

   Открывает index.html в безголовом браузере на ширине 390, подменяет
   ответ двери /рейтинг ответом формы лучшего счёта
   ({ ок, узналиВас, игра, мера:'счёт', режим, строки, продолжение })
   и открывает экран через window.ЭкранРейтинга.открыть('2048').
   Снимок кладётся в tests/снимки/рейтинг-счёт-2048-390.png — его
   оценивает смотритель, здесь картинку не разбираем.

   Кроме снимка — несколько пунктов, чтобы снимок не сняли с пустого
   экрана: экран виден, строки таблицы есть, переключатель режимов виден,
   в шапке «Лучший счёт», запрос ушёл с режимом. Ноль найденного — провал.

   Статический сервер — внутри этого же процесса (как в
   tests/снимок-рейтинг-золото.js), на свободном порту, не 8790/8791/8765;
   гасится через .close() в конце, отдельного PID у него нет.

   Перед запуском: node штаб/браузер-занят.js --ждать
   Запуск:         node tests/снимок-рейтинг-счёт.js
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const http = require('http');
const { chromium, подготовитьПодделку, перехватить } = require('./браузер-робот.js');

const КОРЕНЬ = path.join(__dirname, '..');
const ПАПКА_СНИМКОВ = path.join(__dirname, 'снимки');
const ПУТЬ_СНИМКА = path.join(ПАПКА_СНИМКОВ, 'рейтинг-счёт-2048-390.png');
const ШИРИНА = 390;
const ВЫСОТА = 844;
const АДРЕС_ХОЗЯИНА = '127.0.0.1';
const ЗАПРЕЩЁННЫЕ_ПОРТЫ = [8790, 8791, 8765];

/* Ломающий запуск: «--файл <путь>» — сервер отдаёт вместо
   js/рейтинг-экран.js указанную копию (испорченную во временной папке),
   файл проекта не трогается. Снимок в этом режиме не пишется. */
const НОМЕР_ДОВОДА_ФАЙЛ = process.argv.indexOf('--файл');
const ПОДМЕНА_ЭКРАНА = НОМЕР_ДОВОДА_ФАЙЛ !== -1 ? path.resolve(process.argv[НОМЕР_ДОВОДА_ФАЙЛ + 1] || '') : null;
if (ПОДМЕНА_ЭКРАНА && !fs.existsSync(ПОДМЕНА_ЭКРАНА)) {
  console.error('Нет файла-копии: ' + ПОДМЕНА_ЭКРАНА);
  process.exit(1);
}

const ТИПЫ_ФАЙЛОВ = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.woff2': 'font/woff2'
};

function свободныйПорт() {
  return new Promise((готово, брак) => {
    const проба = http.createServer();
    проба.on('error', брак);
    проба.listen(0, АДРЕС_ХОЗЯИНА, () => {
      const порт = проба.address().port;
      проба.close(() => готово(порт));
    });
  });
}

async function выбратьСвободныйПорт() {
  for (let попытка = 0; попытка < 6; попытка++) {
    const порт = await свободныйПорт();
    if (ЗАПРЕЩЁННЫЕ_ПОРТЫ.indexOf(порт) === -1) return порт;
  }
  throw new Error('не удалось получить свободный порт, отличный от 8790/8791/8765');
}

/** Секреты и служебные папки не раздаём даже своему браузеру. */
function запрещённыйАдрес(адрес) {
  const низ = адрес.toLowerCase();
  if (низ.indexOf('.env') !== -1) return true;
  const части = низ.split(/[\\/]/).filter(Boolean);
  if (части.length && части[0] === 'bot') return true;
  return части.some((часть) => часть.charAt(0) === '.');
}

function поднятьСервер(порт) {
  return new Promise((готово) => {
    const сервер = http.createServer((запрос, ответ) => {
      let адрес;
      try {
        адрес = decodeURIComponent(запрос.url.split('?')[0]);
      } catch (ошибка) {
        ответ.writeHead(400); ответ.end('непонятный адрес'); return;
      }
      if (адрес === '/') адрес = '/index.html';
      if (запрещённыйАдрес(адрес)) { ответ.writeHead(403); ответ.end('доступ закрыт'); return; }
      let файл = path.join(КОРЕНЬ, адрес.replace(/^\/+/, ''));
      if (ПОДМЕНА_ЭКРАНА && адрес === '/js/рейтинг-экран.js') {
        fs.readFile(ПОДМЕНА_ЭКРАНА, (ошибка, данные) => {
          ответ.writeHead(200, { 'Content-Type': ТИПЫ_ФАЙЛОВ['.js'], 'Cache-Control': 'no-store' });
          ответ.end(данные);
        });
        return;
      }
      if (файл !== КОРЕНЬ && !файл.startsWith(КОРЕНЬ + path.sep)) {
        ответ.writeHead(403); ответ.end('файл вне папки проекта'); return;
      }
      fs.readFile(файл, (ошибка, данные) => {
        if (ошибка) { ответ.writeHead(404); ответ.end('не найдено: ' + адрес); return; }
        ответ.writeHead(200, {
          'Content-Type': ТИПЫ_ФАЙЛОВ[path.extname(файл).toLowerCase()] || 'application/octet-stream',
          'Cache-Control': 'no-store'
        });
        ответ.end(данные);
      });
    });
    сервер.listen(порт, АДРЕС_ХОЗЯИНА, () => готово(сервер));
  });
}

/** Ответ сервера лучшего счёта: восемь строк, своя — на пятом месте. */
function ответСчёта(режим) {
  const имена = ['Анна', 'Борис', 'Вера', 'Глеб', 'Вы', 'Дина', 'Егор', 'Жанна'];
  const счёт = [48212, 30150, 20480, 12004, 9876, 5120, 2048, 1024];
  return {
    ок: true,
    узналиВас: true,
    игра: '2048',
    мера: 'счёт',
    режим: режим,
    строки: имена.map((имя, и) => ({
      место: и + 1, имя: имя, значение: счёт[и], дата: '2026-09-29', этоЯ: имя === 'Вы'
    })),
    продолжение: null
  };
}

async function прогон() {
  let провалов = 0;
  let всего = 0;
  function проверить(имя, годно, детали) {
    всего += 1;
    console.log((годно ? '  ok  ' : ' ПЛОХО ') + имя + (детали ? ' (' + детали + ')' : ''));
    if (!годно) провалов += 1;
  }

  const порт = await выбратьСвободныйПорт();
  const сервер = await поднятьСервер(порт);
  console.log('Свой статический сервер: http://' + АДРЕС_ХОЗЯИНА + ':' + порт + '/');

  let браузер = null;
  try {
    браузер = await chromium.launch();
    const контекст = await браузер.newContext({ viewport: { width: ШИРИНА, height: ВЫСОТА }, hasTouch: true });
    const страница = await контекст.newPage();
    const красные = [];
    страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
    страница.on('console', (м) => {
      if (м.type() !== 'error') return;
      const т = м.text();
      if (/telegram-web-app\.js|telegram\.org/.test(т)) return;
      /* Сообщение о битой загрузке адреса не называет — такие разбираем
         ниже по списку «битыеАдреса», где адрес есть. */
      if (/^Failed to load resource/.test(т)) return;
      красные.push('консоль: ' + т);
    });
    /* «Failed to load resource» в консоли не называет адрес — пишем его
       сами, иначе красную консоль не разобрать. */
    const битыеАдреса = [];
    страница.on('requestfailed', (з) => битыеАдреса.push('сбой ' + decodeURIComponent(з.url())));
    страница.on('response', (о) => {
      if (о.status() >= 400) битыеАдреса.push(о.status() + ' ' + decodeURIComponent(о.url()));
    });

    await подготовитьПодделку(страница, { версия: '8.0' });

    const режимыЗапросов = [];
    /* Один перехват на все фоновые двери сервера: /рейтинг отвечает
       таблицей счёта, прочие (/статистика, /пульс, /мой-аватар) — пустым
       отказом, иначе в консоли красные ошибки соединения. */
    await перехватить(страница, /\/(?:рейтинг(?:\?|$)|статистика(?:\?|$)|пульс(?:\?|$)|мой-аватар(?:\?|$))/,
      async function (путь, запрос, адрес) {
        if (/\/рейтинг(?:\?|$)/.test(адрес || '')) {
          let тело = {};
          try { тело = JSON.parse((запрос.postData && запрос.postData()) || '{}'); } catch (о) { тело = {}; }
          режимыЗапросов.push(тело.режим);
          путь.fulfill({
            status: 200,
            contentType: 'application/json; charset=utf-8',
            body: JSON.stringify(ответСчёта(тело.режим || 'classic'))
          });
          return;
        }
        путь.fulfill({ status: 200, contentType: 'application/json; charset=utf-8', body: JSON.stringify({ ок: false }) });
      });

    await страница.goto('http://' + АДРЕС_ХОЗЯИНА + ':' + порт + '/index.html');
    await страница.waitForTimeout(600);
    await страница.evaluate(() => window.ЭкранРейтинга.открыть('2048'));
    await страница.waitForSelector('#экран-рейтинга-игроков.экран--виден', { timeout: 10000 });
    await страница.waitForTimeout(800);

    const замер = await страница.evaluate(() => {
      function виден(узел) {
        if (!узел) return false;
        const р = узел.getBoundingClientRect();
        return р.width > 0 && р.height > 0 && getComputedStyle(узел).visibility !== 'hidden';
      }
      const режимы = document.getElementById('рейтинг-режим');
      const шапка = document.querySelector('#рейтинг-таблица .рейтинг-строка--шапка');
      return {
        строк: document.querySelectorAll('#рейтинг-таблица .рейтинг-строка:not(.рейтинг-строка--шапка)').length,
        карточекПодиума: document.querySelectorAll('#рейтинг-таблица .рейтинг-подиум-карточка').length,
        режимыВидны: виден(режимы),
        вариантов: режимы ? режимы.querySelectorAll('[data-режим]').length : 0,
        шапка: шапка ? шапка.textContent : '',
        силаВидна: виден(document.getElementById('кнопка-рейтинг-сила'))
      };
    });

    проверить('запрос /рейтинг ушёл с режимом «classic»', режимыЗапросов[0] === 'classic',
      'режимы запросов: ' + JSON.stringify(режимыЗапросов));
    проверить('на подиуме три карточки', замер.карточекПодиума === 3, 'карточек: ' + замер.карточекПодиума);
    проверить('под подиумом есть строки списка', замер.строк > 0, 'строк: ' + замер.строк);
    проверить('переключатель режимов виден, в нём два режима', замер.режимыВидны && замер.вариантов === 2,
      'вариантов: ' + замер.вариантов);
    проверить('в шапке списка «Лучший счёт»', замер.шапка.indexOf('Лучший счёт') !== -1, 'шапка: ' + замер.шапка);
    проверить('кнопки «Сила игры» не видно', !замер.силаВидна);

    if (ПОДМЕНА_ЭКРАНА) {
      console.log('Ломающий запуск на копии ' + ПОДМЕНА_ЭКРАНА + ' — снимок не пишется');
    } else {
      if (!fs.existsSync(ПАПКА_СНИМКОВ)) fs.mkdirSync(ПАПКА_СНИМКОВ, { recursive: true });
      await страница.screenshot({ path: ПУТЬ_СНИМКА });
      console.log('Снимок: ' + ПУТЬ_СНИМКА);
    }

    проверить('консоль страницы чистая', красные.length === 0, красные.join(' | '));

    /* Прощаются только два известных сбоя загрузки: telegram-web-app.js
       (робот не пускает страницу в сеть) и значок 2048 в img/рейтинг/ —
       его ещё не нарисовали, и экран честно ставит запасной кружок. Любой
       другой битый адрес — провал. */
    const естьЗапаска = await страница.evaluate(() =>
      !!document.querySelector('.рейтинг-выбор-игры__значок--запаска'));
    const непрощённые = битыеАдреса.filter((строка) => {
      if (/telegram\.org\//.test(строка)) return false;
      if (/\/img\/рейтинг\/2048(@2x)?\.png$/.test(строка) && естьЗапаска) return false;
      return true;
    });
    проверить('других битых загрузок нет', непрощённые.length === 0, непрощённые.join(' | '));
  } finally {
    if (браузер) await браузер.close();
    await new Promise((готово) => сервер.close(готово));
  }

  console.log('');
  console.log('Итого проверок: ' + всего + ', провалов: ' + провалов);
  if (провалов) process.exit(1);
}

прогон().catch(function (ошибка) {
  console.error('Ошибка прогона:', ошибка);
  process.exit(1);
});
