/** Поле «досрочно» так, как его собирает сервер (досрочноДляИгрока из server/партия-по-сети.js):
    на вход — то же «сырьё», что комната кладёт из своего голосования. Руками полей не пишем.
    идёт — голосование есть; мойГолос — 'за' / 'против' / null; мест — сколько мест за столом. */
function полеДосрочно(мест, идёт, мойГолос) {
  const голосующие = МЕСТА.slice(0, мест), я = голосующие[0];
  const голосование = идёт ? { кто: голосующие[1], за: new Set([голосующие[1]]), против: new Set(), докуда: Date.now() + 30000 } : null;
  if (голосование && мойГолос === 'за') голосование.за.add(я);
  if (голосование && мойГолос === 'против') голосование.против.add(я);
  return СЕРВЕР_ПО_СЕТИ.досрочноДляИгрока({ голосование, голосующие, порог: 2, имяПредложившего: ИМЕНА[1], почему: идёт ? 'Голосование о конце партии уже идёт' : null }, я, Date.now());
}

