async function прогнатьОдно(браузер, адрес, размер, св, снимки) {
  const вид = собратьВид(св);
  const контекст = await браузер.newContext({ viewport: { width: размер.w, height: размер.h }, reducedMotion: 'reduce' });
  const ошибки = [];
  const страница = await контекст.newPage();
  страница.on('pageerror', function (о) { ошибки.push('исключение: ' + о.message); });
  страница.on('console', function (с) { if (с.type() === 'error' && !/Failed to load resource/.test(с.text())) ошибки.push('консоль: ' + с.text()); });
  await подготовитьПодделку(страница, {});
  const снять = async function (метка) {
    const файл = path.join(снимки, 'домино-итог-мелочи-' + размер.w + '-' + св.ключ + (метка ? '-' + метка : '') + '.png');
    await страница.screenshot({ path: файл });
    console.log('  снимок: ' + файл);
  };
  const показать = async function (в) {
    const ош = await страница.evaluate(показатьСтол, в);
    проверить(ош === '', размер.w + 'px · ' + св.ключ + ': ' + (св.старая ? '[друзья-старая] ' : '') + 'стол показан через ИграПоСети.показатьВид' + (ош ? ' (' + ош + ')' : ''));
    await страница.waitForTimeout(700);
  };
  try {
    await страница.goto(адрес + 'домино.html?сервер=' + encodeURIComponent('http://127.0.0.1:1'));
    await страница.waitForFunction(function () { return window.ИграПоСети && window.ЛистЕщё; }, null, { timeout: 8000 });
    await страница.waitForTimeout(400);
    await показать(вид);
    const п = размер.w + 'px · ' + св.ключ + ': ';
    if (св.ключ === '5-стол-имена-выход') {
      const имена = await страница.evaluate(замерИмён);
      await снять('');
      const выход = await страница.evaluate(открытьВыход);
      await страница.waitForTimeout(200);
      await снять('выход');
      разобратьИмена(размер, имена, выход, ошибки);
    } else if (св.голосование) {
      let м = await страница.evaluate(замерить);
      проверить(!м.окноОткрыто, п + '[окно-спрятано] ждём моего голоса — окно итога спрятано');
      проверить(м.действие.отключена && /ответьте на голосование/.test(м.действие.текст), п + '[кнопка-результат] «Результат раунда» неактивна с причиной (текст: «' + м.действие.текст + '», отключена: ' + м.действие.отключена + ')');
      проверить(м.действие.яркостьФона < 0.2 && м.действие.контраст >= 4.5, п + '[кнопка-вид] неактивная «Результат раунда» не салатовая: фон тёмный (яркость ' + (м.действие.яркостьФона || 0).toFixed(2) + ', нужно < 0.2), контраст подписи ' + (м.действие.контраст || 0).toFixed(1) + ' (от 4.5)');
      await снять('ждём-голос');
      const ответил = JSON.parse(JSON.stringify(вид)); ответил.версия = ++номерВида; ответил.досрочно = полеДосрочно(св.мест, true, 'за');
      await показать(ответил);
      м = await страница.evaluate(замерить);
      проверить(!м.окноОткрыто, п + '[окно-поверх] я ответил, голосование идёт — окно итога не возвращается поверх');
      проверить(м.действие.отключена && /голосование/.test(м.действие.текст), п + '[кнопка-результат] после ответа тоже неактивна с причиной (текст: «' + м.действие.текст + '»)');
      await снять('ответил');
      const кончилось = JSON.parse(JSON.stringify(ответил)); кончилось.версия = ++номерВида; кончилось.досрочно = полеДосрочно(св.мест, false, null);
      await показать(кончилось);
      м = await страница.evaluate(замерить);
      проверить(м.окноОткрыто, п + '[окно-вернулось] голосование кончилось отказом — окно итога вернулось');
      проверить(ошибки.length === 0, п + 'ошибок в консоли нет' + (ошибки.length ? ': ' + ошибки.join(' | ') : ''));
    } else if (св.ответилСразу) {
      // Ответил до первого показа итога: прятать нечего, окно открывается как обычно (случай 5б).
      const м = await страница.evaluate(замерить);
      проверить(м.окноОткрыто, п + '[окно-5б] я уже ответил, окна не прятали — окно итога открыто');
      проверить(ошибки.length === 0, п + 'ошибок в консоли нет' + (ошибки.length ? ': ' + ошибки.join(' | ') : ''));
    } else if (св.старая) {
      await проверитьСтаруюРазметку(страница, размер, св, ошибки);
    } else if (св.новыйРаунд) {
      await проверитьНовыйРаунд(страница, размер, св, вид, показать, ошибки);
    } else {
      const м = await страница.evaluate(замерить);
      await снять('');
      if (св.гость) разобратьОжидание(размер, м, ошибки);
      else {
        разобратьИтог(св, размер, вид, м, ошибки);
        if (св.фаза === 'конец' && размер.w === 390) await проверитьДрузей(страница, размер, св);
      }
    }
  } finally {
    await контекст.close();
  }
}

/** Новый раунд начался под спрятанным окном: окно прежнего раунда не возвращается, а итог следующего
    раунда, пока голосование ещё идёт, не ложится поверх плашки; когда голосование кончилось — окно раунда есть. */
async function проверитьНовыйРаунд(страница, размер, св, вид, показать, ошибки) {
  const п = размер.w + 'px · ' + св.ключ + ': ';
  const замер = () => страница.evaluate(замерить);
  let м = await замер();
  if (!проверить(м.окноОткрыто, п + 'сначала окно итога открыто (проверка не о том, если нет)')) return;
  const ждёт = JSON.parse(JSON.stringify(вид)); ждёт.версия = ++номерВида; ждёт.досрочно = полеДосрочно(св.мест, true, null);
  await показать(ждёт);
  м = await замер();
  if (!проверить(!м.окноОткрыто, п + '[окно-спрятано] пришло предложение, пока окно было открыто — окно спрятано')) return;
  const играем = собратьВидОдин({ фаза: 'игра', мест: св.мест });
  играем.досрочно = полеДосрочно(св.мест, true, 'за');
  await показать(играем);
  м = await замер();
  проверить(!м.окноОткрыто, п + '[окно-новый-раунд] начался новый раунд — окно прежнего раунда не вернулось');
  const следующий = JSON.parse(JSON.stringify(вид)); следующий.версия = ++номерВида; следующий.домино.раунд = вид.домино.раунд + 1;
  следующий.досрочно = полеДосрочно(св.мест, true, 'за');
  await показать(следующий);
  м = await замер();
  проверить(!м.окноОткрыто, п + '[окно-новый-раунд] итог следующего раунда при идущем голосовании не лёг поверх плашки');
  const конец = JSON.parse(JSON.stringify(следующий)); конец.версия = ++номерВида; конец.досрочно = полеДосрочно(св.мест, false, null);
  await показать(конец);
  м = await замер();
  if (проверить(м.окноОткрыто, п + '[окно-новый-раунд] голосование кончилось — окно итога следующего раунда открылось')) {
    const заголовок = await страница.evaluate(function () { return document.getElementById('дом-итог-заголовок').textContent; });
    проверить(заголовок === 'Раунд №' + (вид.домино.раунд + 1), п + '[окно-новый-раунд] окно — нового раунда (заголовок: «' + заголовок + '»)');
  }
  проверить(ошибки.length === 0, п + 'ошибок в консоли нет' + (ошибки.length ? ': ' + ошибки.join(' | ') : ''));
}

/** Старая страница из кэша: узла середины итога нет. Блок «В друзья» обязан найти себе место в окне,
    а его позднее заполнение — не ронять страницу. */
async function проверитьСтаруюРазметку(страница, размер, св, ошибки) {
  const п = размер.w + 'px · ' + св.ключ + ': ';
  const до = await страница.evaluate(function () {
    const гнездо = document.getElementById('гнездо-друзей');
    return { середины: Boolean(document.getElementById('дом-итог-середина')), окноОткрыто: document.getElementById('дом-результат').open,
      гнездоЕсть: Boolean(гнездо), гнездоВОкне: Boolean(гнездо && document.getElementById('дом-результат').contains(гнездо)) };
  });
  проверить(!до.середины, п + '[друзья-старая] проверка идёт на старой разметке: узла середины итога нет');
  проверить(до.окноОткрыто, п + '[друзья-старая] окно итога открыто');
  проверить(до.гнездоЕсть && до.гнездоВОкне, п + '[друзья-старая] блок «В друзья» создан внутри окна (есть: ' + до.гнездоЕсть + ', в окне: ' + до.гнездоВОкне + ')');
  await страница.evaluate(function () {
    const ящик = document.createElement('div'); ящик.textContent = 'позже заполнился';
    document.getElementById('гнездо-друзей').appendChild(ящик);
  });
  await страница.waitForTimeout(300);
  проверить(ошибки.length === 0, п + '[друзья-старая] после позднего заполнения ошибок в консоли нет' + (ошибки.length ? ': ' + ошибки.join(' | ') : ''));
}

/** Блок «В друзья» заполняется позже: признак «ниже есть ещё» обязан пересчитаться сам (390×844, где всё помещалось). */
async function проверитьДрузей(страница, размер, св) {
  const п = размер.w + 'px · ' + св.ключ + ': ';
  const до = await страница.evaluate(замерить);
  if (!проверить(до.гнездоЕсть && до.середина && !до.середина.ниже, п + '[друзья] блок «В друзья» есть, а признака «ниже» ещё нет (гнездо: ' + до.гнездоЕсть + ', ниже: ' + (до.середина && до.середина.ниже) + ')')) return;
  await страница.evaluate(function () {
    const узел = document.getElementById('гнездо-друзей');
    const ящик = document.createElement('div'); ящик.style.height = '900px'; ящик.textContent = 'позже заполнился';
    узел.appendChild(ящик);
  });
  await страница.waitForTimeout(300);
  const после = await страница.evaluate(замерить);
  проверить(после.середина && после.середина.ниже, п + '[друзья] после позднего заполнения признак «ниже» появился сам, без прокрутки');
  // Край не гасит, когда до конца прокрутки осталось меньше его высоты.
  await страница.evaluate(function () {
    const с = document.getElementById('дом-итог-середина');
    с.scrollTop = с.scrollHeight - с.clientHeight - 10;
  });
  await страница.waitForTimeout(300);
  const у_конца = await страница.evaluate(замерить);
  проверить(у_конца.середина && у_конца.середина.запас > 0 && у_конца.середина.запас < у_конца.середина.край && !у_конца.середина.ниже,
    п + '[край] до конца осталось ' + (у_конца.середина ? Math.round(у_конца.середина.запас) : '?') + ' < края ' + (у_конца.середина ? у_конца.середина.край : '?') + ' — край не гасит (ниже: ' + (у_конца.середина && у_конца.середина.ниже) + ')');
}

async function прогнать(подмены, снимки) {
  fs.mkdirSync(снимки, { recursive: true });
  const сервер = await поднятьСерверФайлов(подмены);
  const адрес = 'http://127.0.0.1:' + сервер.address().port + '/';
  console.log('=== Домино: мелочи окна итога и вида — замеры и снимки ===');
  console.log('файлы: ' + адрес + '\nснимки: ' + снимки);
  // Старая разметка — КОПИЯ домино.html во временной папке без id середины итога (файл проекта не трогаем).
  const папкаСтарой = fs.mkdtempSync(path.join(os.tmpdir(), 'домино-старая-разметка-'));
  const разметка = fs.readFileSync(path.join(ПРОЕКТ, 'домино.html'), 'utf8');
  if (разметка.split(' id="дом-итог-середина"').length - 1 !== 1) throw new Error('в домино.html узел середины итога не найден ровно один раз');
  const копияРазметки = path.join(папкаСтарой, 'домино.html');
  fs.writeFileSync(копияРазметки, разметка.replace(' id="дом-итог-середина"', ''), 'utf8');
  const серверСтарой = await поднятьСерверФайлов(Object.assign({}, подмены, { 'домино.html': копияРазметки }));
  const адресСтарой = 'http://127.0.0.1:' + серверСтарой.address().port + '/';
  let браузер = null;
  try {
    браузер = await chromium.launch();
    for (const размер of РАЗМЕРЫ) {
      for (const св of СОСТОЯНИЯ) {
        console.log('\n--- ' + размер.w + '×' + размер.h + ' · ' + св.ключ + ' ---');
        await прогнатьОдно(браузер, св.старая ? адресСтарой : адрес, размер, св, снимки);
      }
    }
  } finally {
    if (браузер) await браузер.close();
    сервер.close();
    серверСтарой.close();
    fs.rmSync(папкаСтарой, { recursive: true, force: true });
    console.log('\nСервер файлов закрыт.');
  }
  console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
  process.exitCode = провалов > 0 ? 1 : 0;
}

