/** Кто победил в этом виде (номер места) или -1. Для «игры» — null. */
function победительВида(в) {
  const д = в.домино;
  if (д.фаза === 'конец') return Array.isArray(д.победители) && д.победители.length ? д.победители[0] : -1;
  if (д.фаза === 'итог') return д.итог ? д.итог.победитель : -1;
  return null;
}

function собратьВид(св) {
  for (let i = 0; i < 120; i++) {
    const в = собратьВидОдин(св);
    const ок = в.домино.фаза === св.фаза && (!св.хочуПобедительНеЯ || победительВида(в) > 0);
    if (ок) {
      if (св.гость) в.домино.можноПродолжить = false;
      if (св.естьДосрочно) в.досрочно = полеДосрочно(св.мест, false, null);
      if (св.голосование) в.досрочно = полеДосрочно(св.мест, true, null);
      if (св.ответилСразу) в.досрочно = полеДосрочно(св.мест, true, 'против');
      return в;
    }
  }
  throw new Error('не удалось собрать вид «' + св.ключ + '» за 120 попыток');
}

