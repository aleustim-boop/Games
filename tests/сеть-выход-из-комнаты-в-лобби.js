/* ---------- 8. У настоящих мостов шести игр есть вМеню ---------- */

function мостыИмеютВМеню() {
  раздел('\n8.Мосты шести игр: в их файлах window.ИграПоСети с вМеню');
  for (const { игра, мост } of ШЕСТЬ_ИГР) {
    const файл = path.join(КОРЕНЬ, мост);
    const текст = fs.existsSync(файл) ? fs.readFileSync(файл, 'utf8') : '';
    const начало = текст.lastIndexOf('window.ИграПоСети = {');
    // Мост кончается строкой «};» с тем же отступом, что и его начало:
    // внутри моста бывают свои «};» (объекты в телах методов), по ним резать нельзя.
    const началоСтроки = текст.lastIndexOf('\n', начало) + 1;
    const отступ = начало === -1 ? '' : текст.slice(началоСтроки, начало);
    const конец = начало === -1 ? -1 : текст.indexOf('\n' + отступ + '};', начало);
    const тело = конец === -1 ? '' : текст.slice(начало, конец);
    проверить(тело.length > 0 && /вМеню\s*(\(|:)/.test(тело),
      метка(игра) + мост + ': у моста есть вМеню (' + (тело.length ? 'мост найден' : 'МОСТ НЕ НАЙДЕН') + ')');
  }
}

