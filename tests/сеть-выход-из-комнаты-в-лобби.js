/** Ломающий запуск: каждая поломка — на своей копии, итог таблицей. */
async function ломающийЗапуск() {
  const настоящий = fs.readFileSync(ФАЙЛ_СЕТИ, 'utf8');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'сеть-выход-в-лобби-'));
  const таблица = [];
  try {
    for (const поломка of ПОЛОМКИ) {
      const найдено = сколькоНайдено(настоящий, поломка.найти);
      if (найдено !== 1) {
        проверить(false, 'поломка «' + поломка.имя + '»: строка для порчи найдена ' + найдено +
          ' раз, нужно ровно 1 — проверка устарела');
        таблица.push({ имя: поломка.имя, итог: 'СТРОКА НЕ НАШЛАСЬ (' + найдено + ')', провалов: -1 });
        continue;
      }
      const копия = path.join(папка, 'сеть-' + (таблица.length + 1) + '.js');
      fs.writeFileSync(копия, настоящий.replace(поломка.найти, поломка.заменить), 'utf8');
      ИСХОДНИК_СЕТИ = fs.readFileSync(копия, 'utf8');
      непойманныеОтказы.length = 0;
      const провалыДо = провалов;
      молча = true;
      await всеСлучаи();
      // Дать долететь отказам, брошенным в последних ответах.
      await дождаться();
      молча = false;
      const своих = провалов - провалыДо;
      таблица.push({ имя: поломка.имя, итог: своих > 0 ? 'покраснела' : 'НЕ ПОКРАСНЕЛА', провалов: своих });
    }
  } finally {
    fs.rmSync(папка, { recursive: true, force: true });
  }
  console.log('\nПоломка → сколько провалов дала:');
  for (const строка of таблица) {
    console.log('  ' + строка.имя + ': ' + строка.итог + (строка.провалов >= 0 ? ', провалов ' + строка.провалов : ''));
  }
  console.log('Временная папка с копиями стёрта: ' + (fs.existsSync(папка) ? 'НЕТ' : 'да'));
  return таблица.some(function (строка) { return строка.провалов === 0; });
}

(async function () {
  let слепа = false;
  if (ЛОМАЕМ) слепа = await ломающийЗапуск();
  else {
    await всеСлучаи();
    проверить(проверок >= ПОРОГ_ПРОВЕРОК, 'проверок не меньше порога: ' + проверок + ' ≥ ' + ПОРОГ_ПРОВЕРОК);
  }
  console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);
  if (слепа) {
    console.log('ПРОВЕРКА СЛЕПА: какая-то поломка не дала ни одного провала.');
    process.exit(3);
  }
  process.exit(провалов ? 1 : 0);
})().catch(function (ошибка) {
  console.log('Проверка упала: ' + (ошибка && ошибка.stack || ошибка));
  console.log('Итого проверок: ' + проверок + ', провалов: ' + (провалов + 1));
  process.exit(1);
});
