async function возвратПослеПерезагрузки() {
  раздел('\n10.Плашка «Вернуться к игре» в лобби после перезагрузки → выход в лобби');
  for (const { игра } of ШЕСТЬ_ИГР) {
    const выход = поднятьСеть({ игра: игра, сохранённаяКомната: true });
    await дождаться();
    await вернутьсяПлашкой(выход, игра);
    проверитьЧтоВошли(выход, игра, 'плашкой из лобби');
    выход.узел('кнопка-комната-отмена').нажать();
    await дождаться();
    проверить(выход.виден('экран-лобби') && !выход.виден('экран-друга') && выход.счёт.вМеню === 1,
      метка(игра) + 'плашкой из лобби → «Выйти»: лобби, вМеню позван ' + выход.счёт.вМеню + ' раз');
    await проверитьЧтоУшли(выход, игра, 'плашкой из лобби');

    const пропала = поднятьСеть({ игра: игра, сохранённаяКомната: true });
    await дождаться();
    await вернутьсяПлашкой(пропала, игра);
    проверить(пропала.ответитьНаОпрос(404, { ошибка: 'Комнаты нет' }), метка(игра) + 'плашкой: сервер ответил 404');
    await дождаться();
    проверить(пропала.виден('экран-лобби') && !пропала.виден('экран-друга') && пропала.счёт.вМеню === 1,
      метка(игра) + 'плашкой из лобби, комната пропала: лобби, вМеню позван ' + пропала.счёт.вМеню + ' раз');
  }

  // Автовозврат: человек сам открыл «Игра с другом» — туда и выходит.
  for (const игра of ['шашки', 'нарды']) {
    const с = поднятьСеть({ игра: игра, сохранённаяКомната: true });
    await дождаться();
    с.узел('кнопка-с-другом').нажать();
    await дождаться();
    проверитьЧтоВошли(с, игра, 'автовозврат с «Игра с другом»');
    с.узел('кнопка-комната-отмена').нажать();
    await дождаться();
    проверить(с.виден('экран-друга') && !с.виден('экран-лобби') && с.счёт.вМеню === 0,
      метка(игра) + 'автовозврат с «Игра с другом» → «Выйти»: «Игра с другом», вМеню не звали');
  }

  /* Запоздавший автовозврат (адресов два, выбор идёт секунды): игрок за это
     время ушёл в лобби и сел за стол (метка 'путь'). Гонку адресов здесь не
     строим — берём ту же ветку прямо: сидим в комнате, созданной из лобби,
     и тут срабатывает автовозврат экрана «Игра с другом». Метку он трогать
     не должен — выход всё равно в лобби. */
  for (const игра of ['шашки', 'домино']) {
    const с = поднятьСеть({ игра: игра });
    проверить(await войтиСозданиемИзЛобби(с), метка(игра) + 'запоздавший автовозврат: дверь входа нашлась');
    проверитьЧтоВошли(с, игра, 'запоздавший автовозврат');
    с.узел('кнопка-с-другом').нажать();
    await дождаться();
    проверить(с.виден('экран-друга'), метка(игра) + 'запоздавший автовозврат: экран «Игра с другом» открывался');
    с.узел('кнопка-комната-отмена').нажать();
    await дождаться();
    проверить(с.виден('экран-лобби') && !с.виден('экран-друга') && с.счёт.вМеню === 1,
      метка(игра) + 'запоздавший автовозврат у сидящего в комнате → «Выйти»: лобби, вМеню позван ' +
      с.счёт.вМеню + ' раз (метку «путь» не затёр)');
  }

  // Дурак перезагрузил страницу по той же ссылке: автовозврат, выход — его дверью в лобби.
  const дурак = поднятьСеть({ игра: '', дверь: true, сохранённаяКомната: true, параметр: ссылкаНаСтол('дурак') });
  await дождаться();
  проверитьЧтоВошли(дурак, '', 'перезагрузка по ссылке');
  проверить(дурак.пути('/войти') === 0, метка('') + 'перезагрузка по ссылке: заново не входили, вернулись по пропуску');
  дурак.узел('кнопка-комната-отмена').нажать();
  await дождаться();
  проверить(дурак.счёт.дверь === 1 && !дурак.виден('экран-друга'),
    метка('') + 'перезагрузка по ссылке → «Выйти»: дверь в лобби позвана ' + дурак.счёт.дверь + ' раз, как раньше');
}

/* ---------- 11. мост.вМеню бросил ошибку ---------- */

/** Нажать кнопку, не давая брошенной ошибке уронить весь прогон. */
function нажатьБезПадения(с, id) {
  try { с.узел(id).нажать(); return null; } catch (ошибка) { return ошибка; }
}

function ошибкаВКонсоли(с) {
  return с.предупреждения.some(function (строка) { return строка.indexOf('вМеню') !== -1; });
}

async function вМенюБросает() {
  раздел('\n11.мост.вМеню бросил ошибку → «Игра с другом», ошибка в консоли');
  for (const игра of ['шашки', 'нарды']) {
    const выход = поднятьСеть({ игра: игра, вМенюБросает: true });
    await войтиСозданиемИзЛобби(выход);
    проверитьЧтоВошли(выход, игра, 'вМеню бросает');
    const сбой = нажатьБезПадения(выход, 'кнопка-комната-отмена');
    await дождаться();
    проверить(сбой === null, метка(игра) + '«Выйти» при сломанном вМеню: ошибка не вылетела из кнопки');
    проверить(выход.виден('экран-друга') && !выход.виден('экран-комнаты') && !выход.виден('экран-игры'),
      метка(игра) + '«Выйти» при сломанном вМеню: виден «Игра с другом», не пустая комната');
    проверить(выход.пути('/выйти') === 1, метка(игра) + '«Выйти» при сломанном вМеню: серверу сказано /выйти');
    проверить(ошибкаВКонсоли(выход), метка(игра) + '«Выйти» при сломанном вМеню: ошибка записана в консоль');

    for (const этап of ['ожидание', 'игра']) {
      const как = этап === 'ожидание' ? 'в ожидании' : 'посреди партии';
      const отказовДо = непойманныеОтказы.length;
      const пропала = поднятьСеть({ игра: игра, этап: этап, вМенюБросает: true });
      await войтиСозданиемИзЛобби(пропала);
      пропала.ответитьНаОпрос(404, { ошибка: 'Комнаты нет' });
      await дождаться();
      проверить(непойманныеОтказы.length === отказовДо,
        метка(игра) + 'пропала ' + как + ' при сломанном вМеню: ошибка не вылетела наружу');
      проверить(пропала.виден('экран-друга') && пропала.узел('сообщение-друга').textContent.length > 0 &&
        !пропала.виден('экран-комнаты') && !пропала.виден('экран-игры'),
        метка(игра) + 'пропала ' + как + ' при сломанном вМеню: «Игра с другом» с причиной');
      проверить(пропала.счёт.вМеню === 1,
        метка(игра) + 'пропала ' + как + ': вМеню позван ' + пропала.счёт.вМеню + ' раз (нужно 1)');
      проверить(ошибкаВКонсоли(пропала), метка(игра) + 'пропала ' + как + ': ошибка записана в консоль');
    }
  }
}

