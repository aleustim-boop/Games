    classList: {
      toggle: function (имя, есть) {
        const надо = есть === undefined ? !классы.has(имя) : Boolean(есть);
        if (надо) классы.add(имя); else классы.delete(имя);
        return надо;
      },
      add: function (имя) { классы.add(имя); },
      remove: function (имя) { классы.delete(имя); },
      contains: function (имя) { return классы.has(имя); }
    },
    get className() { return Array.from(классы).join(' '); },
    set className(что) {
      классы.clear();
      String(что || '').split(/\s+/).filter(Boolean).forEach(function (к) { классы.add(к); });
    },
    addEventListener: function (вид, что) { if (вид === 'click') обработчики.push(что); },
    removeEventListener: function () {},
    обработчиков: function () { return обработчики.length; },
