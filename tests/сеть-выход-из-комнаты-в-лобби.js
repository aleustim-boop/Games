function прочитатьМетки() {
  const найдено = ИСХОДНИК_СЕТИ.match(/const МЕТКИ_ИГР = (\{[^}]*\});/);
  if (!найдено) return {};
  const пары = {};
  const строка = найдено[1];
  const разбор = /(\w+): '([^']+)'/g;
  let кусок;
  while ((кусок = разбор.exec(строка)) !== null) пары[кусок[2]] = кусок[1];
  return пары;
}
