// Проверка Р14: серая разбивка очков в итоге («10 очков · 7 областей + 1 столица»), склонения и значок края в журнале.
// Запуск:  node tests/захват-итог-разбивка.js            — обычный прогон (без браузера)
//          node tests/захват-итог-разбивка.js --сломать  — портит КОПИИ экрана и оформления во временной папке, требует провала
// Доводы для ломающих запусков: --файл <путь к js/захват-экран.js>, --css <путь к style-захват.css>.
// Функции вытаскиваются из настоящего захват-экран.js (вторых копий нет) и гоняются на заглушке «Правила».
'use strict';
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const а = process.argv.slice(2);
const довод = (имя) => { const и = а.indexOf(имя); return и === -1 ? null : а[и + 1]; };
const путьЭкрана = довод('--файл') || path.join(КОРЕНЬ, 'js', 'захват-экран.js');
const путьCss = довод('--css') || path.join(КОРЕНЬ, 'style-захват.css');

if (а.includes('--сломать')) сломать();
else process.exit(прогон());

function прогон() {
  const текст = fs.readFileSync(путьЭкрана, 'utf8');
  const css = fs.readFileSync(путьCss, 'utf8');
  let плохо = 0, всего = 0;
  const ждать = (факт, образец, метка) => {
    всего++;
    if (факт !== образец) { плохо++; console.log('ПРОВАЛ — ' + метка + ': вышло ' + JSON.stringify(факт) + ', ждали ' + JSON.stringify(образец)); }
  };
  const взять = (имя) => {
    const н = текст.indexOf('  function ' + имя + '(');
    const к = текст.indexOf('\n  }\n', н);
    if (н < 0 || к < 0) { плохо++; всего++; console.log('ПРОВАЛ — в захват-экран.js нет функции ' + имя + ' (ноль найденного — провал)'); return null; }
    return текст.slice(н, к + 4);
  };
  const части = ['поЧислу', 'разбивкаОчков', 'классЖурналаКрая'].map(взять);
  if (части.some((ч) => ч === null)) { console.log('Итого проверок: ' + всего + ', провалов: ' + плохо); return 1; }
  const f = new Function('Правила', части.join('\n') + '; return { поЧислу, разбивкаОчков, классЖурналаКрая };')({ ЧИСЛА: { очкиЗаСтолицу: 3 } });

  ждать(f.разбивкаОчков({ как: 'живой', очки: 10, областей: 7 }), '7 областей + 1 столица', 'разбивка 10 очков');
  ждать(f.разбивкаОчков({ как: 'живой', очки: 7, областей: 7 }), '7 областей', 'без столиц');
  ждать(f.разбивкаОчков({ как: 'живой', очки: 13, областей: 7 }), '7 областей + 2 столицы', 'две столицы');
  ждать(f.разбивкаОчков({ как: 'живой', очки: 21, областей: 6 }), '6 областей + 5 столиц', 'пять столиц');
  ждать(f.разбивкаОчков({ как: 'живой', очки: 3, областей: 0 }), '1 столица', 'только столица');
  ждать(f.разбивкаОчков({ как: 'живой', очки: 0, областей: 0 }), '', 'пусто');
  ждать(f.разбивкаОчков({ как: 'живой', очки: 5 }), '', 'старая запись без числа областей');
  ждать(f.разбивкаОчков({ как: 'сдался', раунд: 4, очки: 5, областей: 5 }), 'вне игры с раунда 4', 'вышел из игры');
  ждать(f.разбивкаОчков({ как: 'сдался', очки: 5, областей: 5 }), 'вне игры', 'вышел, раунд неизвестен');
  ждать(f.поЧислу(1, 'область', 'области', 'областей'), 'область', 'склонение 1');
  ждать(f.поЧислу(2, 'область', 'области', 'областей'), 'области', 'склонение 2');
  ждать(f.поЧислу(5, 'область', 'области', 'областей'), 'областей', 'склонение 5');
  ждать(f.поЧислу(11, 'область', 'области', 'областей'), 'областей', 'склонение 11');
  ждать(f.поЧислу(21, 'область', 'области', 'областей'), 'область', 'склонение 21');
  ждать(f.классЖурналаКрая('Край «Кряж» ваш'), 'захват-журнал-край', 'край ваш');
  ждать(f.классЖурналаКрая('Край «Кряж» потерян'), 'захват-журнал-край захват-журнал-край--потерян', 'край потерян');
  ждать(f.классЖурналаКрая('Бот 1 взял Брод'), undefined, 'не край');
  // Справка открывается с заголовка (scrollTop = 0 прямо перед открытием окна).
  ждать(/\$\('захват-справка'\)\.scrollTop = 0;\s*\n\s*открытьОкно\('захват-справка'\)/.test(текст), true, 'справка прокручена к началу');
  // Оформление: у обоих классов края есть значок, у «потерян» цвет текста.
  ждать(/\.захват-журнал-край::before\s*,\s*\.захват-журнал-край--потерян::before\s*\{/.test(css), true, 'css: значок края');
  ждать(/\.захват-журнал-край--потерян::before\s*\{\s*background-color:\s*currentColor/.test(css), true, 'css: потерянный край — цветом текста');
  console.log('Итого проверок: ' + всего + ', провалов: ' + плохо);
  return плохо ? 1 : 0;
}

function сломать() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-итог-'));
  const экран = fs.readFileSync(path.join(КОРЕНЬ, 'js', 'захват-экран.js'), 'utf8');
  const css = fs.readFileSync(путьCss, 'utf8');
  const порчи = [
    ['экран', 'области не пишутся', 'if (с.областей > 0) части.push(', 'if (false) части.push('],
    ['экран', 'части склеены запятой, а не «+»', "return части.join(' + ');", "return части.join(', ');"],
    ['экран', 'столицы считаются без деления на цену', '(с.очки - с.областей) / Правила.ЧИСЛА.очкиЗаСтолицу', '(с.очки - с.областей)'],
    ['экран', 'выбывший показан как живой', "if (с.как !== 'живой') return", "if (false) return"],
    ['экран', 'у края пропал класс', "return 'захват-журнал-край' + (", "return 'журнал-край' + ("],
    ['экран', 'потерянный край не отличается', "текст.indexOf('потерян') !== -1 ?", 'false ?'],
    ['экран', 'не-край получает класс', "if (текст.indexOf('Край «') !== 0) return undefined;", ''],
    ['экран', 'склонение 11–14 забыто', 'if (сотня >= 11 && сотня <= 14) return пять;', ''],
    ['экран', 'справка не прокручена к началу', "$('захват-справка').scrollTop = 0;", ''],
    ['css', 'у края пропал значок', '.захват-журнал-край::before, .захват-журнал-край--потерян::before {', '.захват-журнал-кай::before, .захват-журнал-край--потерян::before {'],
    ['css', 'потерянный край снова акцентом', '.захват-журнал-край--потерян::before { background-color: currentColor; }', '']
  ];
  let красных = 0;
  порчи.forEach(function (п, н) {
    const исходник = п[0] === 'экран' ? экран : css;
    if (исходник.split(п[2]).length !== 2) { console.log('ПРОВАЛ — место порчи не найдено ровно один раз: ' + п[1]); return; }
    const путь = path.join(папка, 'п' + н + (п[0] === 'экран' ? '.js' : '.css'));
    fs.writeFileSync(путь, исходник.replace(п[2], () => п[3]));
    const р = spawnSync(process.execPath, [__filename, п[0] === 'экран' ? '--файл' : '--css', путь], { encoding: 'utf8' });
    const красная = р.status === 1 && /ПРОВАЛ/.test(р.stdout);
    if (красная) красных++;
    console.log((красная ? 'КРАСНЕЕТ' : 'НЕ КРАСНЕЕТ (плохо)') + ' — ' + п[1] + ' (код ' + р.status + ')');
  });
  const чист = spawnSync(process.execPath, [__filename], { encoding: 'utf8' });
  console.log('Обычный прогон: код ' + чист.status + ' — ' + чист.stdout.trim().split('\n').pop());
  console.log('Красных: ' + красных + ' из ' + порчи.length);
  process.exit(красных === порчи.length && чист.status === 0 ? 0 : 1);
}
