'use strict';

/* =====================================================================
   СБЕРЕЧЬ ДАННЫЕ ВЛАДЕЛЬЦА НА ВРЕМЯ ПРОВЕРКИ.

   Зачем. В server/данные/ лежат живые файлы владельца: знакомства и
   статистика. Несколько проверок из этой папки поднимают настоящий
   серверный код, а тот пишет туда же — путь к папке зашит в
   server/статистика.js и server/знакомые.js, подменить его нечем.
   Проверки при этом честно чистят память перед замером, а потом
   сбрасывают её на диск — и вместо накопленных чисел владельца на диске
   остаётся пусто. Так уже случилось: 8 сентября знакомства и статистика
   были стёрты запуском проверок.

   Как пользоваться:
       const { сберечь } = require('./сберечь-данные.js');
       сберечь();      // снимок сразу, возврат — сам, при любом исходе

   Возврат делается и при обычном выходе, и когда проверку прервали
   с клавиатуры, и когда она упала. Возвращается ровно то, что было:
   изменённые файлы переписываются обратно, а те, которых до нас не было,
   убираются как наш след.
   ===================================================================== */

const fs = require('fs');
const path = require('path');

const ПАПКА = path.resolve(__dirname, '..', 'server', 'данные');

/** Что лежит в папке данных прямо сейчас: имя файла → его содержимое. */
function снятьСнимок() {
  const снимок = new Map();
  if (!fs.existsSync(ПАПКА)) return снимок;
  for (const имя of fs.readdirSync(ПАПКА)) {
    const полный = path.join(ПАПКА, имя);
    try {
      if (!fs.statSync(полный).isFile()) continue;
      снимок.set(имя, fs.readFileSync(полный));
    } catch (сбой) { /* файл исчез прямо сейчас — не наша забота */ }
  }
  return снимок;
}

/** Вернуть папку в то состояние, что было на снимке. Возвращает список дел. */
function вернутьКакБыло(снимок) {
  const сделано = [];
  if (!fs.existsSync(ПАПКА)) {
    if (снимок.size === 0) return сделано;
    fs.mkdirSync(ПАПКА, { recursive: true });
  }
  for (const [имя, содержимое] of снимок) {
    const полный = path.join(ПАПКА, имя);
    const сейчас = fs.existsSync(полный) ? fs.readFileSync(полный) : null;
    if (сейчас && сейчас.equals(содержимое)) continue;
    fs.writeFileSync(полный, содержимое);
    сделано.push('вернул ' + имя);
  }
  for (const имя of fs.readdirSync(ПАПКА)) {
    const полный = path.join(ПАПКА, имя);
    if (!fs.statSync(полный).isFile()) continue;
    if (снимок.has(имя)) continue;
    fs.unlinkSync(полный);
    сделано.push('убрал наш след ' + имя);
  }
  return сделано;
}

/**
 * Снять снимок и пообещать вернуть всё назад при любом исходе.
 * Возвращает функцию «вернуть сейчас», если она зачем-то понадобится руками.
 */
function сберечь() {
  const снимок = снятьСнимок();
  let ужеВернули = false;

  function вернуть(повод) {
    if (ужеВернули) return;
    ужеВернули = true;
    let дела = [];
    try { дела = вернутьКакБыло(снимок); } catch (сбой) {
      console.log('  (данные владельца вернуть не вышло: ' + сбой.message + ')');
      return;
    }
    if (дела.length) console.log('  (' + повод + ': ' + дела.join(', ') + ')');
  }

  process.on('exit', function () { вернуть('данные владельца возвращены'); });
  process.on('SIGINT', function () { вернуть('прервали с клавиатуры'); process.exit(130); });
  process.on('uncaughtException', function (сбой) {
    вернуть('проверка упала');
    console.error('Проверка упала: ' + (сбой && сбой.stack || сбой));
    process.exit(2);
  });

  return вернуть;
}

module.exports = { сберечь: сберечь, снятьСнимок: снятьСнимок, вернутьКакБыло: вернутьКакБыло, ПАПКА: ПАПКА };
