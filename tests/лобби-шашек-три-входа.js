const path = require('path');
const { spawn } = require('child_process');
const { chromium, безTelegram } = require('./браузер-робот.js');

const ПОРТ = 8958;
const АДРЕС = 'http://127.0.0.1:' + ПОРТ + '/шашки.html';
const КОРЕНЬ_ПРОЕКТА = path.join(__dirname, '..');
// Довод — путь к копии для ломающего прогона; без довода раздаём сам проект.
const КОРЕНЬ_РАЗДАЧИ = process.argv[2] ? path.resolve(process.argv[2]) : КОРЕНЬ_ПРОЕКТА;

let всегоПроверок = 0;
let провалов = 0;
function проверить(условие, слова) {
  всегоПроверок++;
  if (условие) console.log('  ок   — ' + слова);
  else { провалов++; console.log('  ПЛОХО— ' + слова); }
}
const спать = (мс) => new Promise((готово) => setTimeout(готово, мс));

/** Поднимает tests/локальный-сервер.js дочерним процессом на своём порту. */
function поднятьСервер() {
  const сервер = spawn('node', [
    path.join(__dirname, 'локальный-сервер.js'),
    String(ПОРТ)
  ], {
    env: Object.assign({}, process.env, { КОРЕНЬ_СЕРВЕРА: КОРЕНЬ_РАЗДАЧИ }),
    stdio: 'pipe'
  });

  return new Promise((resolve, reject) => {
    let вывод = '';
    const таймаут = setTimeout(() => reject(new Error('Сервер не поднялся за 5 секунд')), 5000);
    сервер.stdout.on('data', (данные) => {
      вывод += данные.toString();
      if (вывод.includes('запущен')) { clearTimeout(таймаут); resolve(сервер); }
    });
    сервер.stderr.on('data', (данные) => console.log('  ошибка сервера: ' + данные.toString().trim()));
    сервер.on('error', (е) => { clearTimeout(таймаут); reject(е); });
  });
}

async function основной() {
  console.log('Раздаю файлы из: ' + КОРЕНЬ_РАЗДАЧИ);
  const сервер = await поднятьСервер();
  let браузер = null;

  try {
    браузер = await chromium.launch();
    const контекст = await браузер.newContext({ viewport: { width: 390, height: 844 } });
    const страница = await контекст.newPage();
    const ошибки = [];
    страница.on('pageerror', (о) => ошибки.push('исключение: ' + о.message));
    страница.on('console', (с) => {
      if (с.type() === 'error' && /Failed to load resource/.test(с.text())) return;
      if (с.type() === 'error') ошибки.push('консоль: ' + с.text());
    });

    await безTelegram(страница);
    await страница.goto(АДРЕС);
    await страница.waitForTimeout(400);

    /* ---------------- 1. Первый шаг — РОВНО три карточки ---------------- */
    console.log('\n=== 1. Первый шаг: ровно три карточки-входа, без переключателей ===');

    const карточки = await страница.evaluate(() => {
      const лобби = document.getElementById('экран-лобби');
      if (!лобби) return null;
      const узлы = Array.from(лобби.querySelectorAll('.карточка-входа'));
      return узлы.map((узел) => ({
        id: узел.id,
        название: (узел.querySelector('.карточка-входа__название') || {}).textContent || '',
        подпись: (узел.querySelector('.карточка-входа__подпись') || {}).textContent || ''
      }));
    });

    проверить(карточки !== null, 'узел #экран-лобби нашёлся на странице');

    const ОЖИДАЕМЫЕ = [
      { id: 'лобби-найти-игру', название: 'Играть онлайн', подпись: 'Соперники со всего мира' },
      { id: 'лобби-боты', название: 'Играть с ботом', подпись: 'Тренировка в своём темпе' },
      { id: 'лобби-друзья', название: 'Позвать друга', подпись: 'Сыграйте с другом по ссылке' }
    ];

    if (карточки) {
      проверить(карточки.length === 3,
        'карточек-входов на лобби ровно три (нашлось: ' + карточки.length + ' — ' +
        карточки.map((к) => к.id || '(без id)').join(', ') + ')');

      ОЖИДАЕМЫЕ.forEach((ожид, номер) => {
        const факт = карточки[номер];
        проверить(Boolean(факт), 'карточка №' + (номер + 1) + ' (' + ожид.id + ') нашлась на месте ' + (номер + 1));
        if (!факт) return;
        проверить(факт.id === ожид.id,
          'карточка №' + (номер + 1) + ': id «' + ожид.id + '» (а вышел «' + факт.id + '»)');
        проверить(факт.название.trim() === ожид.название,
          'карточка «' + ожид.id + '»: название «' + ожид.название + '» (а вышло «' + факт.название.trim() + '»)');
        проверить(факт.подпись.trim() === ожид.подпись,
          'карточка «' + ожид.id + '»: подпись «' + ожид.подпись + '» (а вышло «' + факт.подпись.trim() + '»)');
      });
    } else {
      // #экран-лобби не нашёлся — три карточки заведомо не проверить,
      // явно проваливаем и остальные пункты блока, а не молчим нулём.
      проверить(false, 'карточек-входов на лобби ровно три (лобби не найдено вовсе)');
      ОЖИДАЕМЫЕ.forEach((ожид) => проверить(false, 'карточка «' + ожид.id + '» нашлась (лобби не найдено вовсе)'));
    }

    const переключателиНаЛобби = await страница.evaluate(() => {
      const лобби = document.getElementById('экран-лобби');
      if (!лобби) return null;
      return Array.from(лобби.querySelectorAll('[id^="лобби-уровень-"], [id^="лобби-время-"]')).map((у) => у.id);
    });
    проверить(переключателиНаЛобби !== null, 'узел #экран-лобби нашёлся (для проверки переключателей)');
    if (переключателиНаЛобби !== null) {
      проверить(переключателиНаЛобби.length === 0,
        'на первом шаге нет переключателей уровня/контроля времени' +
        (переключателиНаЛобби.length ? ' — а они есть: ' + переключателиНаЛобби.join(', ') : ''));
    }

    /* ---------------- 2. «Играть с ботом» открывает второй шаг ---------------- */
    console.log('\n=== 2. Карточка «Играть с ботом» открывает шаг с уровнем и кнопкой «Начать» ===');

    await страница.click('#лобби-боты');
    await страница.waitForTimeout(300);

    const второйШаг = await страница.evaluate(() => {
      const лобби = document.getElementById('экран-лобби');
      const шагБота = document.getElementById('экран-бота-шашек');
      const кнопкаНачать = document.getElementById('кнопка-с-ботом');
      return {
        лоббиСкрылось: Boolean(лобби && !лобби.classList.contains('экран--виден')),
        шагВиден: Boolean(шагБота && шагБота.classList.contains('экран--виден')),
        уровеньЕсть: Boolean(document.getElementById('уровень-лёгкий') &&
          document.getElementById('уровень-обычный') && document.getElementById('уровень-сложный')),
        контрольЕсть: Boolean(document.getElementById('время-нет') && document.getElementById('время-пять')),
        кнопкаНачатьЕсть: Boolean(кнопкаНачать),
        кнопкаНачатьТекст: кнопкаНачать ? кнопкаНачать.textContent.trim() : ''
      };
    });

    проверить(второйШаг.лоббиСкрылось, 'после клика «Играть с ботом» первый шаг (лобби) скрылся');
    проверить(второйШаг.шагВиден, 'после клика «Играть с ботом» виден #экран-бота-шашек');
    проверить(второйШаг.уровеньЕсть, 'на втором шаге видны три кнопки уровня бота');
    проверить(второйШаг.контрольЕсть, 'на втором шаге видны кнопки контроля времени');
    проверить(второйШаг.кнопкаНачатьЕсть, 'на втором шаге есть кнопка «Начать» (#кнопка-с-ботом)');
    проверить(второйШаг.кнопкаНачатьТекст === 'Начать',
      'кнопка называется «Начать» (а вышло «' + второйШаг.кнопкаНачатьТекст + '»)');

    const старойКнопкиВдвоёмНет = await страница.evaluate(() =>
      document.getElementById('кнопка-бота-вдвоём') === null);
    проверить(старойКнопкиВдвоёмНет,
      'на втором шаге старой кнопки «кнопка-бота-вдвоём» больше нет — путь «вдвоём» один');

    /* ---------------- 3. «Назад» со второго шага — на первый шаг ---------------- */
    console.log('\n=== 3. «Назад» со второго шага возвращает на первый, а не на старый экран ===');

    await страница.click('#кнопка-бота-назад');
    await страница.waitForTimeout(300);

    const послеНазад = await страница.evaluate(() => {
      const лобби = document.getElementById('экран-лобби');
      const режимов = document.getElementById('экран-режимов');
      const шагБота = document.getElementById('экран-бота-шашек');
      return {
        лоббиВиден: Boolean(лобби && лобби.classList.contains('экран--виден')),
        режимовВиден: Boolean(режимов && режимов.classList.contains('экран--виден')),
        шагСкрыт: Boolean(шагБота && !шагБота.classList.contains('экран--виден'))
      };
    });

    проверить(послеНазад.лоббиВиден, '«Назад» вернул на первый шаг (#экран-лобби виден)');
    проверить(!послеНазад.режимовВиден, '«Назад» НЕ увёл на старый запасной экран (#экран-режимов скрыт)');
    проверить(послеНазад.шагСкрыт, 'второй шаг (#экран-бота-шашек) скрылся после «Назад»');

    проверить(ошибки.length === 0, 'красных ошибок в консоли нет' +
      (ошибки.length ? ' — а они есть: ' + ошибки.join(' | ') : ''));

    /* ---------- 4. «Вдвоём на одном телефоне»: видна на первом шаге (390), ----------
       клик заводит партию ИМЕННО вдвоём, без бота (владелец 24.09) ---------- */
    console.log('\n=== 4. «Вдвоём на одном телефоне»: видна на 390, клик заводит партию без бота ===');

    // Лобби сейчас снова видно (блок 3 вернул на первый шаг) — новый
    // контекст заводить незачем, кнопка уже на экране.
    const доВдвоём = await страница.evaluate(() => {
      const кнопка = document.getElementById('лобби-вдвоём');
      const входитВКарточкиВхода = Boolean(кнопка && кнопка.closest('.лобби__входы'));
      return {
        видна: Boolean(кнопка && кнопка.offsetParent !== null),
        текст: (кнопка && кнопка.textContent || '').trim(),
        классМелкая: Boolean(кнопка && кнопка.classList.contains('кнопка--мелкая')),
        внеКарточекВхода: Boolean(кнопка) && !входитВКарточкиВхода
      };
    });
    проверить(доВдвоём.видна, '«лобби-вдвоём» видна на первом шаге на ширине 390');
    проверить(доВдвоём.текст === 'Вдвоём на одном телефоне',
      'текст кнопки — ровно «Вдвоём на одном телефоне» (нашлось: «' + доВдвоём.текст + '»)');
    проверить(доВдвоём.классМелкая, '«лобби-вдвоём» — мелкая кнопка (класс «кнопка--мелкая»)');
    проверить(доВдвоём.внеКарточекВхода, '«лобби-вдвоём» НЕ входит в тройку карточек .лобби__входы');

    // Партия обязана начаться ИМЕННО вдвоём, без бота: слушатели вешаем
    // ДО клика — сама кнопка «кнопка-вдвоём» нажимается программно
    // (js/шашки-лобби.js), настоящего клика мышью на ней не видно.
    // Клик — через evaluate, а не page.click(): на ломающем прогоне узла
    // «лобби-вдвоём» может не быть вовсе, и обычный click() 30 секунд
    // ждал бы появления невидимой кнопки, роняя весь прогон исключением
    // вместо честного и быстрого провала.
    await страница.evaluate(() => {
      window.__клики = { вдвоём: 0, сБотом: 0 };
      document.getElementById('кнопка-вдвоём')?.addEventListener('click', () => { window.__клики.вдвоём++; });
      document.getElementById('кнопка-с-ботом')?.addEventListener('click', () => { window.__клики.сБотом++; });
      document.getElementById('лобби-вдвоём')?.click();
    });
    await страница.waitForTimeout(400);
    const послеВдвоём = await страница.evaluate(() => ({
      доскаВидна: Boolean(document.getElementById('экран-шашек')?.classList.contains('экран--виден')),
      клики: window.__клики
    }));
    проверить(послеВдвоём.доскаВидна, 'клик по «лобби-вдвоём» открывает доску (#экран-шашек)');
    проверить(послеВдвоём.клики.вдвоём === 1 && послеВдвоём.клики.сБотом === 0,
      'запущена партия ИМЕННО вдвоём без бота (нажата «кнопка-вдвоём», «кнопка-с-ботом» — нет)');

    await контекст.close();

    /* ---------- 5. «Вдвоём на одном телефоне»: видна на широком экране (1280) ---------- */
    console.log('\n=== 5. «Вдвоём на одном телефоне»: видна на первом шаге на ширине 1280 ===');

    const окноШироко = await браузер.newContext({ viewport: { width: 1280, height: 900 } });
    const страницаШироко = await окноШироко.newPage();
    const ошибкиШироко = [];
    страницаШироко.on('pageerror', (о) => ошибкиШироко.push('исключение: ' + о.message));
    страницаШироко.on('console', (с) => {
      if (с.type() === 'error' && /Failed to load resource/.test(с.text())) return;
      if (с.type() === 'error') ошибкиШироко.push('консоль: ' + с.text());
    });
    await безTelegram(страницаШироко);
    await страницаШироко.goto(АДРЕС);
    await страницаШироко.waitForTimeout(400);

    const видШироко = await страницаШироко.evaluate(() => {
      const кнопка = document.getElementById('лобби-вдвоём');
      return {
        видна: Boolean(кнопка && кнопка.offsetParent !== null),
        текст: (кнопка && кнопка.textContent || '').trim()
      };
    });
    проверить(видШироко.видна, '«лобби-вдвоём» видна на первом шаге на ширине 1280');
    проверить(видШироко.текст === 'Вдвоём на одном телефоне',
      'текст кнопки на 1280 — ровно «Вдвоём на одном телефоне» (нашлось: «' + видШироко.текст + '»)');
    проверить(ошибкиШироко.length === 0, 'красных ошибок в консоли на 1280 нет' +
      (ошибкиШироко.length ? ' — а они есть: ' + ошибкиШироко.join(' | ') : ''));

    await окноШироко.close();
  } finally {
    if (браузер) await браузер.close();
    сервер.kill();
    console.log('Сервер на ' + ПОРТ + ' погашен (по PID дочернего процесса).');
  }

  console.log('\nИтого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
  if (провалов > 0) process.exit(1);
}

основной().catch(function (е) {
  console.error('ПРОВАЛ ЗАПУСКА: ' + (е && е.stack || е));
  process.exit(1);
});
