function ломающиеЗапуски() {
  console.log('Ломающие запуски на копии');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'деберц-время-'));
  const текст = fs.readFileSync(ЭКРАН, 'utf8');
  let поломок = 0, покраснело = 0, нашлось = true;
  try {
    ПОЛОМКИ.forEach((поломка, номер) => {
      поломок++;
      const сколько = текст.split(поломка.было).length - 1;
      if (сколько !== 1) {
        console.log('  ПРОВАЛ  строка для порчи ' + поломка.имя + ' найдена ' + сколько + ' раз (нужно ровно один): ' + поломка.было);
        нашлось = false;
        return;
      }
      const копия = path.join(папка, 'копия-' + номер + '.js');
      fs.writeFileSync(копия, текст.replace(поломка.было, () => поломка.стало));
      const итог = spawnSync(process.execPath, [__filename, '--экран', копия], { encoding: 'utf8', timeout: 120000 });
      const вывод = (итог.stdout || '') + (итог.stderr || '');
      const строкаИтога = вывод.match(/Итого проверок: (\d+), провалов: (\d+)/) || [];
      const красные = вывод.split('\n').filter(с => с.includes('ПРОВАЛ  '));
      const покраснела = итог.status === 1 && Number(строкаИтога[2]) > 0 && красные.some(с => с.includes(поломка.провалит));
      if (покраснела) { покраснело++; console.log('  ок      порча ' + поломка.имя + ' краснеет на «' + поломка.провалит + '»'); }
      else console.log('  ПРОВАЛ  порча ' + поломка.имя + ' НЕ покраснела как надо: код ' + итог.status + ', ' + (строкаИтога[0] || 'итога нет') + ', нужна «' + поломка.провалит + '», красные: ' + красные.join(' | ').slice(0, 300) + (красные.length ? '' : '\n' + вывод.slice(-400)));
    });
  } finally {
    fs.rmSync(папка, { recursive: true, force: true });
  }
  console.log('Поломок ' + поломок + ', покраснело ' + покраснело);
  return нашлось && поломок === покраснело && поломок >= 5;
}

