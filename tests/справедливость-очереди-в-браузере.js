/* =====================================================================
   СПРАВЕДЛИВА ЛИ ОЧЕРЕДЬ — ГЛАЗАМИ ЧЕЛОВЕКА ЗА ЭКРАНОМ

   Зачем. Живой игрок пожаловался не на незаконный ход, а на то, что его
   перестали звать: стол на четверых парами, один выбыл — и дальше играли
   двое, а он досматривал партию зрителем. Автопрогон такое ловит изнутри,
   по полям партии. А эта проверка смотрит ровно то же самое СНАРУЖИ —
   по экрану: по строке подсказки и по плашкам соперников. Ничего, кроме
   того, что видит человек, она не знает.

   Как пользоваться (из консоли браузера, до начала партии):
       УскорительПауз.выключить();  // ОБЯЗАТЕЛЬНО: см. про ШАГ ниже
       Очередь.начать();     // следит и копит
       Очередь.отчёт();      // что вышло
       Очередь.стоп();

   Что копит:
     • подходов в партии — считаем по мигу, когда стол пустеет;
     • в скольких из них человек был нападающим или отбивающимся;
     • «хвост» — сколько последних подходов подряд человека не звали;
     • когда с плашки соперника пропали карты (кто-то вышел из партии)
       и сколько раз человека позвали ПОСЛЕ этого.

   Про строку подсказки. Игра пишет в неё, что делать, и по ней всегда
   видно роль человека: «Ваш ход» и «Ваше слово» — нападает, «Отбивайтесь»
   и «Отбиться нечем» — отбивается. Ролей соперника («Бот 3 отбивает
   карту») мы не разбираем вовсе: нам важен только сам человек.
   ===================================================================== */

(function () {
  'use strict';

  /* Как часто заглядываем на экран.

     ВАЖНОЕ ПРЕДУПРЕЖДЕНИЕ, И ОНО СТОИЛО МНЕ ЛОЖНОЙ ТРЕВОГИ.
     Эта проверка НЕ ГОДИТСЯ вместе с ускорителем пауз
     (tests/ускоритель-пауз-в-браузере.js). Ускоритель укорачивает паузы
     игры в шесть раз, и ход бота начинает умещаться между двумя моими
     взглядами на экран. Роль, которую человек в этом подходе играл,
     я тогда просто не вижу — и записываю «не звали» там, где звали.

     Замерено на одних и тех же двадцати парных партиях: с ускорителем
     самый длинный «хвост» вышел 8, без ускорителя на тех же условиях —
     4, а замер изнутри игры (tests/автопрогон-правил-компанией.js,
     63991 партия) говорит, что больше 6 здоровая игра не даёт вовсе.
     То есть восьмёрка была враньём прибора, а не находкой.

     Правило простое: меряешь очередь — выключи ускоритель
     («УскорительПауз.выключить()»). Партий выйдет меньше, зато числа
     будут настоящие. А для счёта партий и поиска поломок ускоритель
     по-прежнему хорош — он врёт только про то, КТО и КОГДА играл. */
  const ШАГ = 150;

  /* Слова, по которым человек узнаёт свою роль. Берутся с экрана как есть;
     если игра однажды перепишет подсказки, проверка это заметит — счётчик
     ролей встанет в ноль там, где человек явно играл, и это будет видно
     в отчёте отдельной строкой «роль по экрану не опозналась ни разу». */
  const Я_НАПАДАЮ = ['Ваш ход', 'Ваше слово', 'подкиньте или', 'подкинуть нечем'];
  const Я_ОТБИВАЮСЬ = ['Отбивайтесь', 'Отбиться нечем', 'Укажите карту на столе', 'переведите'];

  let таймер = null;
  let состояние = null;

  function чистое() {
    return {
      подходов: 0,
      сНами: 0,               // подходов, где человек был в главной роли
      хвост: 0,               // подходов подряд без нас — прямо сейчас
      хвостМакс: 0,
      ролейНеОпозналось: 0,
      выбылКтоТо: false,      // хоть один соперник вышел из партии
      ктоВышел: '',
      подходовПослеВыбытия: 0,
      сНамиПослеВыбытия: 0,
      ходилиВПодходе: {},
      отбивалисьВПодходе: {},
      вышлиВПодходе: '',
      подробно: [],
      этотПодходНаш: false,
      столБылНеПуст: false,
      журнал: []
    };
  }

  function подсказка() {
    const у = document.getElementById('подсказка');
    return у ? (у.textContent || '') : '';
  }

  function мояРоль() {
    const т = подсказка();
    for (const с of Я_ОТБИВАЮСЬ) if (т.indexOf(с) !== -1) return 'отбиваюсь';
    for (const с of Я_НАПАДАЮ) if (т.indexOf(с) !== -1) return 'нападаю';
    return '';
  }

  /* Кто вышел из партии — видно по плашке соперника: игра пишет на ней
     метку «без карт». Считать оставшиеся карты по плашке нельзя: пока
     карты соперника лежат на столе, игра нарочно пишет там другое,
     чтобы «0 карт» посреди подхода не читалось как «игрока больше нет».
     Первый заход этой проверки считал именно карты — и не увидел ни
     одного выбывшего за шесть партий подряд. */
  /* Что игра пишет на плашках соперников. Метка там одна на все случаи:
     «без карт» — вышел из партии, «ходит» — нападает, «отбивается» —
     отбивается. Больше ниоткуда роли соперника снаружи не видно, и это
     хорошо: проверка читает ровно то же, что читает человек.

     Карты по плашке считать нельзя: пока карты соперника лежат на столе,
     игра нарочно пишет там другое, чтобы «0 карт» посреди подхода
     не читалось как «игрока больше нет». Первый заход этой проверки
     считал именно карты — и не увидел ни одного выбывшего за шесть
     партий подряд. */
  function плашки() {
    const узлы = document.querySelectorAll('#соперники .соперник, #полоса-соперников > *');
    const список = [];
    for (const п of узлы) {
      const имя = п.querySelector('.соперник__имя');
      const метка = п.querySelector('.соперник__метка');
      список.push({
        имя: имя ? (имя.textContent || '').trim() : '?',
        метка: метка ? (метка.textContent || '').trim() : ''
      });
    }
    return список;
  }

  function ктоВышел() {
    return плашки().filter(function (п) { return п.метка.indexOf('без карт') !== -1; })
                   .map(function (п) { return п.имя; });
  }

  /* Кто из соперников сейчас в главных ролях — по тем же меткам. */
  function ролиСоперников() {
    const все = плашки();
    const ходит = все.filter(function (п) { return п.метка === 'ходит'; }).map(function (п) { return п.имя; });
    const отб = все.filter(function (п) { return п.метка === 'отбивается'; }).map(function (п) { return п.имя; });
    return { ходит: ходит.join(','), отбивается: отб.join(',') };
  }

  function столПуст() {
    const с = document.getElementById('стол');
    if (!с) return true;
    return с.querySelectorAll('.карта, .пара').length === 0;
  }

  function шаг() {
    const с = состояние;
    if (!с) return;

    const роль = мояРоль();
    if (роль) с.этотПодходНаш = true;

    const вышли = ктоВышел();
    if (вышли.length > 0) { с.выбылКтоТо = true; с.ктоВышел = вышли.join(', '); }
    const роли = ролиСоперников();
    if (роли.ходит) с.ходилиВПодходе[роли.ходит] = true;
    if (роли.отбивается) с.отбивалисьВПодходе[роли.отбивается] = true;
    if (вышли.length) с.вышлиВПодходе = вышли.join(',');

    const пусто = столПуст();
    if (!пусто) с.столБылНеПуст = true;

    // Стол опустел после того, как на нём что-то лежало — подход кончился.
    if (пусто && с.столБылНеПуст) {
      с.подходов++;
      if (с.выбылКтоТо) с.подходовПослеВыбытия++;
      if (с.этотПодходНаш) {
        с.сНами++;
        if (с.выбылКтоТо) с.сНамиПослеВыбытия++;
        с.хвост = 0;
      } else {
        с.хвост++;
        if (с.хвост > с.хвостМакс) с.хвостМакс = с.хвост;
      }
      с.журнал.push((с.этотПодходНаш ? 'звали' : 'НЕ звали') +
        (с.выбылКтоТо ? ' (кто-то уже вышел)' : ''));
      /* Подробная запись: кто нападал, кто отбивался, кто уже вышел.
         Нужна, чтобы длинный обход можно было не только посчитать,
         но и ОПИСАТЬ: в каком положении человека перестают звать. */
      с.подробно.push({
        подход: с.подходов,
        меня: с.этотПодходНаш ? 'звали' : 'не звали',
        нападал: Object.keys(с.ходилиВПодходе).join('/') || 'я или неясно',
        отбивался: Object.keys(с.отбивалисьВПодходе).join('/') || 'я или неясно',
        вышли: с.вышлиВПодходе || '—'
      });
      с.ходилиВПодходе = {};
      с.отбивалисьВПодходе = {};
      с.этотПодходНаш = false;
      с.столБылНеПуст = false;
    }
  }

  window.Очередь = {
    начать: function () {
      состояние = чистое();
      if (таймер) clearInterval(таймер);
      таймер = setInterval(шаг, ШАГ);
      return 'слежу за очередью';
    },
    стоп: function () { if (таймер) clearInterval(таймер); таймер = null; return 'перестала следить'; },
    отчёт: function () {
      if (!состояние) return null;
      const с = состояние;
      return {
        подходов: с.подходов,
        насЗвали: с.сНами,
        хвостМакс: с.хвостМакс,
        ктоТоВышел: с.выбылКтоТо,
        ктоИменноВышел: с.ктоВышел,
        подходовПослеВыбытия: с.подходовПослеВыбытия,
        насЗвалиПослеВыбытия: с.сНамиПослеВыбытия,
        последние: с.журнал.slice(-20),
        подробно: с.подробно
      };
    }
  };
})();
