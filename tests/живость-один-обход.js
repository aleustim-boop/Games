#!/usr/bin/env node
'use strict';

/* =====================================================================
   ПРОВЕРКА: сторож дашборда обходит все сессии исполнителей ОДИН РАЗ
   на сбор, а не дважды, и не заглядывает в сессии, где давно ничего
   не менялось.

   Была поломка. штаб/сбор.js собирает данные дашборда так:
     1. живость.живостьИсполнителей() — сама обходит все сессии;
     2. сторожПростоя.собрать() (штаб/кто-молчит.js) — тоже обходит
        все сессии заново, теми же файлами.
   Итог — два полных обхода на один показ страницы, а файлов сессий уже
   сотни и число растёт. Правка: штаб/сбор.js обходит сессии один раз
   (штаб/живость.js, записиИсполнителей) и отдаёт готовый результат
   обеим функциям через их же «подделку» — контракт, который раньше был
   только для проверок. Отдельно живость.js пропускает сессии, чья
   папка записей (tasks/subagents) не менялась дольше суток — читать
   такие незачем, это закрытые дела.

   ЧЕМ ПРОВЕРЯЕМ. Все файлы сессий — поддельные, во временной папке:
   os.tmpdir() и профиль Claude (CLAUDE_CONFIG_DIR) на время теста
   подменяются на свои временные пути, поэтому настоящие записи
   исполнителей этот тест не трогает и не читает вовсе.

   1. Свежая сессия видна, старая (папка records не менялась двое
      суток) — пропущена: живость.записиИсполнителей() возвращает
      только свежую запись.
   2. штаб/сбор.js.собратьВсё() обходит сессии ровно один раз за вызов:
      считаем обращения к живость.записиИсполнителей() через подмену
      функции на объекте модуля (сбор.js и штаб/кто-молчит.js держат
      ссылку на тот же объект — require одного и того же файла).

   ── Код выхода ──
   Обычный прогон (node tests/живость-один-обход.js):
     0 — обе проверки прошли; 1 — нашли расхождение (текст ✗ выше итога).

   Ломающий прогон (node tests/живость-один-обход.js --папка=<путь>):
     <путь> — заранее подготовленная ВНЕШНЯЯ копия штаб/ (вне проекта),
     в которой штаб нарочно вернул двойной обход или убрал пропуск
     старых сессий. Тот же тест гоняется против неё вместо настоящей
     штаб/ — обязан покраснеть. Настоящие файлы штаб/ этот тест не
     трогает и не читает: путь к копии приходит только доводом.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const assert = require('assert');

let тестов = 0;
let провалов = 0;
function проверить(условие, текст) {
  тестов++;
  if (условие) {
    console.log('  ✓ ' + текст);
  } else {
    провалов++;
    console.log('  ✗ ' + текст);
  }
}

/* Папка штаба: по умолчанию настоящая, для ломающего прогона — копия,
   путь к которой приходит доводом --папка=<путь>. */
const ДОВОД_ПАПКИ = process.argv.find(function (a) { return a.startsWith('--папка='); });
const ПУТЬ_ШТАБА = ДОВОД_ПАПКИ
  ? path.resolve(ДОВОД_ПАПКИ.slice('--папка='.length))
  : path.join(__dirname, '..', 'штаб');

console.log(ДОВОД_ПАПКИ ? 'ЛОМАЮЩИЙ ПРОГОН: копия штаб/ — ' + ПУТЬ_ШТАБА : 'обычный прогон: ' + ПУТЬ_ШТАБА);

/* ---------------------------------------------------------------------
   Песочница: своя временная os.tmpdir() и свой временный профиль Claude.
   Создаётся в реальном системном tmpdir (это безопасно — обычная
   практика для тестов), а вот САМИ живость.js/сбор.js после подмены
   будут искать записи исполнителей только в ней.
------------------------------------------------------------------------ */
const ВР_КОРЕНЬ = fs.mkdtempSync(path.join(os.tmpdir(), 'живость-один-обход-'));
const ВР_TMPDIR = path.join(ВР_КОРЕНЬ, 'tmp');
const ВР_ПРОФИЛЬ = path.join(ВР_КОРЕНЬ, 'профиль');
fs.mkdirSync(ВР_TMPDIR, { recursive: true });
fs.mkdirSync(ВР_ПРОФИЛЬ, { recursive: true });

const прежнийCLAUDE_CONFIG_DIR = process.env.CLAUDE_CONFIG_DIR;
process.env.CLAUDE_CONFIG_DIR = ВР_ПРОФИЛЬ; // живость.js читает эту переменную при загрузке — подменяем до require

const прежнийTmpdir = os.tmpdir;
os.tmpdir = function () { return ВР_TMPDIR; }; // тот же объект 'os' видят и живость.js, и сбор.js (кэш require)

function прибраться() {
  os.tmpdir = прежнийTmpdir;
  if (прежнийCLAUDE_CONFIG_DIR === undefined) delete process.env.CLAUDE_CONFIG_DIR;
  else process.env.CLAUDE_CONFIG_DIR = прежнийCLAUDE_CONFIG_DIR;
  try { fs.rmSync(ВР_КОРЕНЬ, { recursive: true, force: true }); } catch (ошибка) { /* временная папка — не критично */ }
}

(async function () {
  try {
    const живость = require(path.join(ПУТЬ_ШТАБА, 'живость.js'));
    const сбор = require(path.join(ПУТЬ_ШТАБА, 'сбор.js'));

    // Тот же КОРЕНЬ, что вычисляют сами живость.js/сбор.js (path.resolve(__dirname,'..')
    // от их собственного расположения) — так имя папки проекта совпадёт.
    const корень = path.resolve(path.join(ПУТЬ_ШТАБА, '..'));
    const имяПроекта = живость.имяПапкиПроекта(корень);

    const путьTasks = function (сессия) { return path.join(ВР_TMPDIR, 'claude', имяПроекта, сессия, 'tasks'); };
    const путьSubagents = function (сессия) { return path.join(ВР_ПРОФИЛЬ, 'projects', имяПроекта, сессия, 'subagents'); };

    // Свежая сессия: файлы созданы прямо сейчас — должна быть видна целиком.
    fs.mkdirSync(путьTasks('сессия-свежая'), { recursive: true });
    fs.writeFileSync(path.join(путьTasks('сессия-свежая'), 'fresh0001111.output'), 'работает');
    fs.mkdirSync(путьSubagents('сессия-свежая'), { recursive: true });
    fs.writeFileSync(path.join(путьSubagents('сессия-свежая'), 'agent-fresh0002222.jsonl'), '{}');

    // Старая сессия: и файлы, и сами папки состарены на двое суток — порог в
    // живость.js сутки, поэтому такую сессию читать не должны вовсе.
    fs.mkdirSync(путьTasks('сессия-старая'), { recursive: true });
    fs.writeFileSync(path.join(путьTasks('сессия-старая'), 'old0003333.output'), 'дело закрыто');
    fs.mkdirSync(путьSubagents('сессия-старая'), { recursive: true });
    fs.writeFileSync(path.join(путьSubagents('сессия-старая'), 'agent-old0004444.jsonl'), '{}');

    const двоеСутокНазад = new Date(Date.now() - 2 * 24 * 60 * 60 * 1000);
    // Порядок важен: сначала старим файл, потом папку — иначе создание файла
    // (уже случившееся выше) переписало бы mtime папки обратно на «сейчас».
    fs.utimesSync(path.join(путьTasks('сессия-старая'), 'old0003333.output'), двоеСутокНазад, двоеСутокНазад);
    fs.utimesSync(путьTasks('сессия-старая'), двоеСутокНазад, двоеСутокНазад);
    fs.utimesSync(path.join(путьSubagents('сессия-старая'), 'agent-old0004444.jsonl'), двоеСутокНазад, двоеСутокНазад);
    fs.utimesSync(путьSubagents('сессия-старая'), двоеСутокНазад, двоеСутокНазад);

    console.log('\n1. Свежие сессии видны, старые пропущены:');

    const момент = Date.now();
    проверить(
      живость.папкаНедавноЖила(путьTasks('сессия-свежая'), момент) === true,
      'папка свежей сессии считается недавно живой'
    );
    проверить(
      живость.папкаНедавноЖила(путьTasks('сессия-старая'), момент) === false,
      'папка сессии старше суток считается заброшенной'
    );

    const обход = живость.записиИсполнителей(момент);
    проверить(обход.найдена === true, 'записи исполнителей нашлись (во временной песочнице)');
    const имена = обход.записи.map(function (з) { return з.имя; }).sort();
    проверить(
      имена.indexOf('fresh0001111') !== -1 && имена.indexOf('fresh0002222') !== -1,
      'обе свежие записи (tasks и subagents) видны'
    );
    проверить(
      имена.indexOf('old0003333') === -1 && имена.indexOf('old0004444') === -1,
      'обе записи старой сессии пропущены (папка не менялась дольше суток)'
    );

    console.log('\n2. Один обход сессий на один сбор дашборда:');

    /* Считаем не вызовы JS-функции, а настоящие обращения к диску:
       живость.живостьИсполнителей() вызывает записиИсполнителей() через
       замыкание (не через module.exports), поэтому патч свойства объекта
       такой вызов не увидит — так и было поймано на этом самом тесте при
       первой попытке. fs.readdirSync — общий для всего процесса модуль,
       его вызов виден независимо от того, как до него добрались.
       Ровно два таких вызова происходят внутри одного обхода — по разу на
       корневую папку записей (tmpdir) и корневую папку профиля — поэтому
       один обход даёт 2 обращения, два обхода — 4. */
    const корневаяПутьЗаписей = path.join(ВР_TMPDIR, 'claude', имяПроекта);
    const корневаяПутьПрофиля = path.join(ВР_ПРОФИЛЬ, 'projects', имяПроекта);
    let обращенийКДиску = 0;
    const оригиналReaddirSync = fs.readdirSync;
    fs.readdirSync = function (путь) {
      if (путь === корневаяПутьЗаписей || путь === корневаяПутьПрофиля) обращенийКДиску++;
      return оригиналReaddirSync.apply(fs, arguments);
    };

    let итогСбора = null;
    let бедаСбора = null;
    try {
      итогСбора = await сбор.собратьВсё();
    } catch (ошибка) {
      бедаСбора = ошибка;
    } finally {
      fs.readdirSync = оригиналReaddirSync;
    }

    проверить(бедаСбора === null, 'сбор.собратьВсё() отработал без исключения' + (бедаСбора ? (': ' + бедаСбора.message) : ''));
    проверить(
      обращенийКДиску === 2,
      'штаб/сбор.js обошёл сессии исполнителей ровно один раз за сбор (обращений к корневым папкам: '
        + обращенийКДиску + ', ожидали 2 — по разу на tmpdir и профиль)'
    );
    // Побочная сверка: раз обход был один, живые записи из него всё равно
    // дошли и до живости, и до сторожа простоя — значит переиспользование,
    // а не просто «забыли посчитать».
    if (итогСбора && итогСбора.исполнители) {
      проверить(
        итогСбора.исполнители.всегоЗаписей === обход.записи.length,
        'результат единого обхода дошёл до живости исполнителей (' + итогСбора.исполнители.всегоЗаписей + ' записей)'
      );
    }

    console.log('\nИтого проверок: ' + тестов + ', провалов: ' + провалов);
    прибраться();
    process.exitCode = провалов ? 1 : 0;
  } catch (ошибка) {
    console.error('ПРОВЕРКА УПАЛА: ' + (ошибка && ошибка.stack ? ошибка.stack : ошибка));
    прибраться();
    process.exitCode = 1;
  }
})();
