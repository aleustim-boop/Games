/* =====================================================================
   ЗАЩЁЛКИ ВХОДА В СЕТЬ: второе нажатие не должно проскакивать мимо очереди.

   Что чиним. В js/сеть.js у «сестьЗаСтол» и «создатьОткрытыйСтол» есть
   защёлки (входимВИгру / создаёмИгру) — они не дают уйти в игру дважды
   от двойного нажатия. Раньше защёлка поднималась ПОСЛЕ решитьСпорАдресов()
   (стука на оба адреса сервера, если их вписано два) — и пока этот стук
   летел, второе нажатие видело входимВИгру ещё false и проскакивало мимо
   проверки. Теперь защёлку поднимают СРАЗУ, а снимают в конце цепочки на
   любом исходе — успех, отказ сервера или брошенная ошибка.

   Как проверяем. Поднимаем js/сеть.js в песочнице vm с поддельным window,
   подделываем fetch — он не отвечает сам, а ждёт, пока проверка вручную
   решит нужный запрос. Так видно ровно то окно времени, где раньше
   проскакивало второе нажатие.

   Шум от самого файла. При загрузке с подписью Telegram сеть.js сама
   заводит фоновую «отметку присутствия» (стучится в /друзья-онлайн) и,
   если в памяти два разных адреса, сама же затевает спор адресов ещё до
   первого нашего вызова. Поэтому запросы ищем не по номеру по счёту,
   а по хвосту адреса (/здоровье, /сесть, /создать) — иначе проверка
   ловила бы не тот запрос и зависала бы, ничего не проверив.

   Запуск обычной проверки:      node tests/защёлки-входа-в-сети.js
   Запуск ломающего (на копии):  node tests/защёлки-входа-в-сети.js --сломать <путь-к-копии>
   Выход 0 — провалов нет.
   ===================================================================== */

