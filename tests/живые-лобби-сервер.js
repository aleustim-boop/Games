/* =====================================================================
   ЖИВЫЕ ЛОББИ, ЭТАП Э5: режиссёр столов личин подключён к серверу.

   Что проверяем (только node, браузера нет; боевой 8790 не трогаем):
     1) сервер, запущенный НАПРЯМУЮ (node server/сервер.js <порт>
        --без-памяти), сам открывает столы личин. Видно это только за
        ключом, в /штаб-онлайн (комнатВсего, комнатСЛюдьми, столовЛичин):
        через ПЕРВЫЙ_ШАГ_МС режиссёра столовЛичин > 0, комнатСЛюдьми = 0.
        Открытый всем /здоровье при этом — ровно {живой, комнат, коммит},
        комнат = 0 (пустые столы личин не считаются: скрипты выкатки ищут
        "комнат":0,), и слова «личин» в нём нет — личины снаружи люди;
     2) ЛИЧИНЫ=выкл — столов нет, в журнале «режиссёр … выключен»;
     3) ЛОББИ_ЛИЧИН=выкл — столов нет;
     4) ЛОББИ_ПОРОГ_ЛЮДЕЙ=1 и один человек ждёт в подборе — столов нет:
        ищущий считается живым человеком. Человека ставим в очередь прямо
        в памяти дочернего сервера (запускалка зовёт подбор.встатьВОчередь
        того же экземпляра модуля): через HTTP /подбор нужна подпись
        initData настоящим токеном бота, а он — секрет из bot/.env;
     5) файл, подключённый МОДУЛЕМ (как это делают проверки), режиссёра не
        запускает. Тут же запускаем режиссёра руками — столы появляются,
        значит способ смотреть работает и ноль выше не случайный;
     6) подбор.сколькоЖдут(): двое на разных полках — 2, сведённая пара
        не считается, одного отменили — 1.

   Как поднимаем сервер. Обычный прогон: node server/сервер.js напрямую.
   Ломающий прогон и запуск 4: запускалка (этот же файл с доводом
   --копия-главным) компилирует текст сервера на месте настоящего файла
   и делает его главным модулем — require.main === module, как при прямом
   запуске. Порча «ноль» — копия БЕЗ изменений через ту же запускалку:
   обязана дать код 0, иначе порчи а/в/г/д/е/ж ничего не доказывают.

   Ломающие запуски (порча — на КОПИИ во временной папке или подменой
   в памяти; файлы проекта не трогаются):
     node tests/живые-лобби-сервер.js --сломать все
   «ноль» обязана дать код 0, остальные — код 1. Порча, не нашедшая своей
   строки, — код 2.
   ===================================================================== */

