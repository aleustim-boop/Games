// Где лежит файл проекта: общий помощник проверок (node).
//
// Зачем: код игр разложен по папкам «игры/<игра>/» и «общее/{js,css,casual,шрифты}/».
// Проверке незачем помнить, в какой папке лежит «сеть.js»: она называет ИМЯ файла,
// а место находит помощник. Имена файлов кода уникальны, поэтому имени хватает.
// Помощник работает и до переезда (js/, css в корне, шрифты/), и после него.
//
//   const Пути = require('./пути-проекта.js');
//   Пути.путь('сеть.js')              полный путь к файлу в проекте
//   Пути.путь('сеть.js', копия)       то же место, но в копии проекта (во временной папке)
//   Пути.отКорня('сеть.js')           «общее/js/сеть.js» — от корня, через прямой слэш
//   Пути.папкиКода()                  какие папки копировать, чтобы увезти весь код: ['игры','общее']
//   Пути.всеJs()                      имена всех скриптов игры (замена чтению папки js)
//   Пути.создатьПапкиКода(копия)      пустые папки кода в копии — чтобы класть туда файлы поштучно
//   Пути.скопироватьКод(откуда, куда) весь код из одного корня в другой
//
// Двойник имени или ненайденное имя — исключение с понятным текстом: молча вернуть
// «что-нибудь» нельзя, проверка прочитала бы не тот файл и осталась зелёной.
//
// Запуск файла сам по себе — его проверка:  node tests/пути-проекта.js
// Ломающий запуск:  node tests/пути-проекта.js --корень=<пустая папка>  — обязан покраснеть.

'use strict';
const fs = require('fs');
const path = require('path');

const ПРОЕКТ = path.join(__dirname, '..');
const НОВЫЕ = ['игры', 'общее'];
// Единственный файл, который нарочно лежит дважды: рабочий в общее/css и копия в корне
// (её догружают открытые сессии со старым telegram.js). Рабочим считаем новый.
const ОКОНЧАНИЯ_КОДА = /\.(js|css)$/;

function этоПапка(п) {
  try { return fs.statSync(п).isDirectory(); } catch (e) { return false; }
}

/** Подпапки одной папки (только первый уровень). */
function подпапки(корень, папка) {
  const полная = path.join(корень, папка);
  if (!этоПапка(полная)) return [];
  return fs.readdirSync(полная).filter((имя) => этоПапка(path.join(полная, имя))).map((имя) => папка + '/' + имя);
}

/** Папки кода этого корня: сперва новые места, потом старые. */
function местаКода(корень) {
  const новые = [...подпапки(корень, 'игры'), ...подпапки(корень, 'общее')];
  const старые = ['js', 'шрифты'].filter((п) => этоПапка(path.join(корень, п)));
  return { новые, старые };
}

/** Таблица «имя файла → места от корня». Читает диск заново при каждом вызове: копии наполняются на ходу. */
function таблица(корень) {
  const места = местаКода(корень);
  const имена = new Map(); // имя → { новые: [], старые: [] }
  const добавить = (вид, папка, имя) => {
    if (!имена.has(имя)) имена.set(имя, { новые: [], старые: [] });
    имена.get(имя)[вид].push(папка ? папка + '/' + имя : имя);
  };
  const файлы = (папка) => fs.readdirSync(path.join(корень, папка || '.'), { withFileTypes: true }).filter((з) => з.isFile()).map((з) => з.name);
  for (const папка of места.новые) for (const имя of файлы(папка)) добавить('новые', папка, имя);
  for (const папка of места.старые) for (const имя of файлы(папка)) добавить('старые', папка, имя);
  // В корне кодом считаем только оформление: страницы и документы — не наша забота.
  if (этоПапка(корень)) for (const имя of файлы('')) if (имя.endsWith('.css')) добавить('старые', '', имя);
  return имена;
}

const памятьТаблиц = new Map(); // корень → таблица; при промахе перечитываем

function найти(имя, корень) {
  const ищем = (заново) => {
    if (заново || !памятьТаблиц.has(корень)) памятьТаблиц.set(корень, таблица(корень));
    const т = памятьТаблиц.get(корень);
    return т.get(имя) || (ОКОНЧАНИЯ_КОДА.test(имя) ? null : т.get(имя + '.js')) || null;
  };
  return ищем(false) || ищем(true);
}

/** Место файла от корня, через прямой слэш. Корень по умолчанию — сам проект. */
function отКорня(имя, корень) {
  if (typeof имя !== 'string' || !имя) throw new Error('пути-проекта: имя файла не названо (получено: ' + String(имя) + ')');
  // Дали уже путь («js/сеть.js», «общее/js/сеть.js») — берём только имя: место знает помощник.
  const чистое = имя.replace(/\\/g, '/').split('/').pop();
  const где = path.resolve(корень || ПРОЕКТ);
  // В копии файла может ещё не быть (его туда только собираются положить) — тогда место берём из проекта.
  const запись = найти(чистое, где) || (где !== path.resolve(ПРОЕКТ) ? найти(чистое, path.resolve(ПРОЕКТ)) : null);
  if (!запись) {
    throw new Error('пути-проекта: файла «' + чистое + '» нет ни в игры/*/, ни в общее/*/, ни в js/, ни в шрифты/, ни среди css в корне (корень: ' + где + ')');
  }
  const места = запись.новые.length ? запись.новые : запись.старые;
  if (места.length !== 1) {
    throw new Error('пути-проекта: имя «' + чистое + '» лежит в нескольких местах: ' + места.join(', ') + ' — имена файлов кода обязаны быть уникальны');
  }
  const место = места[0];
  // Имя без окончания («домино-правила») возвращаем тоже без окончания — так его ждёт require.
  return место.endsWith('/' + чистое) || место === чистое ? место : место.slice(0, -3);
}

/** Полный путь к файлу. С корнем — то же место внутри копии проекта. */
function путь(имя, корень) {
  return path.join(path.resolve(корень || ПРОЕКТ), отКорня(имя, корень));
}

/**
 * Папки, которые надо скопировать, чтобы увезти код. Без довода — весь код
 * (прежние «js» и «шрифты»); с доводом 'шрифты' — только то, где лежат шрифты.
 */
function папкиКода(что, корень) {
  const где = path.resolve(корень || ПРОЕКТ);
  const естьНовые = НОВЫЕ.filter((п) => этоПапка(path.join(где, п)));
  if (естьНовые.length) return что === 'шрифты' ? ['общее'] : естьНовые;
  const старые = (что === 'шрифты' ? ['шрифты'] : ['js', 'шрифты']).filter((п) => этоПапка(path.join(где, п)));
  if (!старые.length) throw new Error('пути-проекта: в ' + где + ' нет ни игры/ и общее/, ни js/ — папок кода не найдено');
  return старые;
}

/** Имена всех скриптов игры (без папок) — замена прежнему чтению папки js. */
function всеJs(корень) {
  const где = path.resolve(корень || ПРОЕКТ);
  const т = таблица(где);
  памятьТаблиц.set(где, т);
  const имена = [];
  for (const [имя, запись] of т) {
    const места = запись.новые.length ? запись.новые : запись.старые;
    if (имя.endsWith('.js') && места.some((м) => !м.startsWith('шрифты/'))) имена.push(имя);
  }
  if (!имена.length) throw new Error('пути-проекта: в ' + где + ' не найдено ни одного скрипта игры');
  return имена.sort();
}

/** Создаёт в копии пустые папки кода — те же, что в проекте. Возвращает корень копии. */
function создатьПапкиКода(куда, откуда) {
  const места = местаКода(path.resolve(откуда || ПРОЕКТ));
  const список = места.новые.length ? места.новые : места.старые;
  if (!список.length) throw new Error('пути-проекта: в проекте не найдено папок кода');
  for (const папка of список) fs.mkdirSync(path.join(куда, папка), { recursive: true });
  return куда;
}

/** Копирует код из одного корня в другой. что: 'js' (по умолчанию) — весь код, 'шрифты' — только шрифты. */
function скопироватьКод(откуда, куда, что) {
  const где = path.resolve(откуда || ПРОЕКТ);
  const послеПереезда = НОВЫЕ.some((п) => этоПапка(path.join(где, п)));
  let папки;
  if (послеПереезда) папки = что === 'шрифты' ? ['общее/шрифты'] : НОВЫЕ.filter((п) => этоПапка(path.join(где, п)));
  else папки = [что === 'шрифты' ? 'шрифты' : 'js'];
  for (const папка of папки) {
    if (!этоПапка(path.join(где, папка))) throw new Error('пути-проекта: нечего копировать — нет папки ' + path.join(где, папка));
    fs.cpSync(path.join(где, папка), path.join(куда, папка), { recursive: true });
  }
  return куда;
}

/** Это прежняя общая папка «js», которой после переезда нет? */
function этоУшедшаяJs(папка) {
  return path.basename(папка) === 'js' && !этоПапка(папка);
}

/**
 * Файл в названной папке. Если папка — прежняя «<корень>/js», которой больше нет,
 * место ищется по имени в том же корне. Для проверок с доводом «--папка=<копия>»:
 * в своей копии файл лежит прямо в папке, в проекте — по папкам игр.
 */
function вПапке(папка, имя) {
  const прямо = path.join(папка, имя);
  if (fs.existsSync(прямо) || !этоУшедшаяJs(папка)) return прямо;
  return путь(имя, path.dirname(папка));
}

/** Имена скриптов в названной папке; для прежней «<корень>/js» — все скрипты игры этого корня. */
function всеJsВПапке(папка) {
  if (!этоУшедшаяJs(папка)) return fs.readdirSync(папка);
  return всеJs(path.dirname(папка));
}

/** Сосед файла по имени; если рядом его нет (соседи разъехались по папкам) — место в проекте. Только для чтения. */
function рядомИлиВПроекте(файл, имя) {
  const рядом = path.join(path.dirname(файл), имя);
  if (fs.existsSync(рядом) || fs.existsSync(рядом + '.js')) return рядом;
  return путь(имя);
}

/** Путь, записанный по-старому («style.css», «js/сеть.js», «index.html»): лежит там — отдаём как есть, нет — ищем по имени. */
function изСтарого(старыйПуть, корень) {
  const прямо = path.join(path.resolve(корень || ПРОЕКТ), старыйПуть);
  if (fs.existsSync(прямо)) return прямо;
  return путь(старыйПуть, корень);
}

module.exports = { ПРОЕКТ, путь, отКорня, папкиКода, всеJs, создатьПапкиКода, скопироватьКод, вПапке, всеJsВПапке, рядомИлиВПроекте, изСтарого };

