/* ---------------------------------------------------------------------
   А1) Вырезаем тело function view(g, me) балансом фигурных скобок —
   тело не однострочное, поэтому «до первой }» тут недостаточно.
   ------------------------------------------------------------------- */
function вырезатьТелоПоСигнатуре(текст, сигнатура) {
  const совпадение = сигнатура.exec(текст);
  if (!совпадение) return null;
  let i = совпадение.index + совпадение[0].length; // сразу после открывающей «{»
  let глубина = 1;
  const начало = i;
  while (i < текст.length && глубина > 0) {
    const ch = текст[i];
    if (ch === '{') глубина++;
    else if (ch === '}') глубина--;
    i++;
  }
  if (глубина !== 0) return null; // скобки не сошлись — вырезать не удалось
  return текст.slice(начало, i - 1);
}

