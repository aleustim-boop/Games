/** Ищет ключ имяКлюча на любой глубине значения (объекты и массивы).
 * Возвращает путь до первой находки или null, если ключа нигде нет. */
function найтиКлючГлубоко(значение, имяКлюча, путь) {
  if (значение === null || typeof значение !== 'object') return null;
  if (Array.isArray(значение)) {
    for (let i = 0; i < значение.length; i++) {
      const рез = найтиКлючГлубоко(значение[i], имяКлюча, путь + '[' + i + ']');
      if (рез) return рез;
    }
    return null;
  }
  for (const k of Object.keys(значение)) {
    if (k === имяКлюча) return путь + '.' + k;
    const рез = найтиКлючГлубоко(значение[k], имяКлюча, путь + '.' + k);
    if (рез) return рез;
  }
  return null;
}

/** Ищет подстроку буквально во всём JSON значения (утечка на любой глубине). */
function jsonСодержит(значение, подстрока) {
  return JSON.stringify(значение).indexOf(подстрока) !== -1;
}

/** Проверяет перенос ВСЕХ полей VIEW_FIELDS разом для одного вида;
 * при провале в тексте шага перечисляет, какие именно поля подвели —
 * так вывод остаётся по одной строке на игрока, а не по одной на поле. */
function проверитьПереносПолей(g, v, метка) {
  const плохие = [];
  for (const имя of списокПолей) {
    const исходное = g[имя];
    if (исходное === undefined) {
      if (имя in v) плохие.push(имя + ' (должно отсутствовать, но есть)');
    } else {
      const есть = Object.prototype.hasOwnProperty.call(v, имя);
      if (!есть || JSON.stringify(v[имя]) !== JSON.stringify(исходное)) {
        плохие.push(имя + (есть ? ' (не совпадает глубоко)' : ' (нет в виде)'));
      }
    }
  }
  шаг(плохие.length === 0,
    метка + ': все ' + списокПолей.length + ' поля VIEW_FIELDS перенесены верно' +
    (плохие.length ? ' — ПРОБЛЕМЫ: ' + плохие.join(', ') : ''));
}

/* Пункт (6), обратное покрытие: множество верхних ключей g, увиденных
 * за весь прогон (по всем состояниям), без seed/decks — каждый из них
 * обязан быть в VIEW_FIELDS, иначе экран получает поле, забытое в
 * списке, и все проверки (1)-(5) выше этого не заметят (они смотрят
 * только на то, что список УЖЕ включает). */
const накопленныеКлючиG = new Set();

/** Полная батарея проверок view() для одного состояния партии g,
 * прогоняется по всем игрокам. Подкладывает и убирает g.утечка сама,
 * чтобы g осталась чистой для дальнейшей игры ботом. */
function проверитьСостояние(g, метка) {
  for (const k of Object.keys(g)) накопленныеКлючиG.add(k);

  const ожидаемыйАктёр = P.who(g);
  const ожидаемыйСклад = P.stock(g);

  g.утечка = { секрет: 'НЕ-ДОЛЖНО-УТЕЧЬ-777' };

  for (let i = 0; i < g.players.length; i++) {
    const v = P.view(g, i);
    const подпись = метка + ', игрок ' + i;

    шаг(Boolean(v) && typeof v === 'object', подпись + ': view() вернула объект');
    if (!v) continue;

    // (1) seed и decks — нигде, ни сверху, ни на любой глубине.
    const путьSeed = найтиКлючГлубоко(v, 'seed', 'v');
    шаг(!путьSeed, подпись + ': ключа «seed» нигде в виде нет' + (путьSeed ? ' (нашли: ' + путьSeed + ')' : ''));
    const путьDecks = найтиКлючГлубоко(v, 'decks', 'v');
    шаг(!путьDecks, подпись + ': ключа «decks» нигде в виде нет' + (путьDecks ? ' (нашли: ' + путьDecks + ')' : ''));

    // (2) перенос всех разрешённых полей.
    проверитьПереносПолей(g, v, подпись);

    // (3) чужое поле «утечка» не попадает в вид ни ключом, ни текстом.
    шаг(!('утечка' in v), подпись + ': чужого поля «утечка» в виде нет');
    шаг(!jsonСодержит(v, 'НЕ-ДОЛЖНО-УТЕЧЬ-777'), подпись + ': JSON вида не содержит текста чужого поля «утечка»');

    // (4) вид — глубокая копия: правка вида не трогает исходную партию.
    const деньгиДо = g.players[0].money;
    const очередьДлинаДо = g.queue.length;
    if (v.players && v.players[0]) v.players[0].money = 999999999;
    if (Array.isArray(v.queue)) v.queue.push({ подложено: true });
    шаг(g.players[0].money === деньгиДо, подпись + ': правка v.players[0].money не изменила партию g');
    шаг(g.queue.length === очередьДлинаДо, подпись + ': правка v.queue (push) не изменила партию g');

    // (5) me, actor, stock — на месте и правдивы.
    шаг(v.me === i, подпись + ': v.me === ' + i + ' (получили: ' + v.me + ')');
    шаг(v.actor === ожидаемыйАктёр, подпись + ': v.actor совпадает с P.who(g) (' + ожидаемыйАктёр + ', получили: ' + v.actor + ')');
    шаг(JSON.stringify(v.stock) === JSON.stringify(ожидаемыйСклад),
      подпись + ': v.stock совпадает с P.stock(g) (' + JSON.stringify(ожидаемыйСклад) + ', получили: ' + JSON.stringify(v.stock) + ')');
  }

  delete g.утечка; // партия должна остаться чистой для дальнейшей игры ботом
}

try {
  const g = P.create(4, 20260930, false);

  // Состояние 1: сразу после раздачи. На свежей партии поле «resume»
  // ни разу не устанавливалось — это честный пример undefined-поля,
  // которого в виде быть не должно вовсе.
  шаг(g.resume === undefined, 'на свежей партии поле g.resume пока не установлено (undefined) — годится для проверки отсутствия');
  проверитьСостояние(g, 'свежая партия');

  // Состояние 2: после серии ходов ботом — auction/trade/queue/events
  // уже не пустые, есть шанс появления «resume» и прочих полей со
  // значениями, отличными от начальных.
  let сделаноХодов = 0;
  const ПРЕДЕЛ_ХОДОВ = 80;
  while (сделаноХодов < ПРЕДЕЛ_ХОДОВ) {
    const p = P.who(g);
    if (p < 0) break; // партия завершена
    const m = B.move(g);
    if (!m) break;
    try {
      P.action(g, p, m);
    } catch (сбойХода) {
      break; // бот упёрся в редкий крайний случай — розыгрыш прекращаем, но не проваливаем страж
    }
    сделаноХодов++;
  }
  шаг(сделаноХодов >= 10, 'бот сделал хотя бы 10 ходов до проверки второго состояния (сделал: ' + сделаноХодов + ')');

  проверитьСостояние(g, 'после ' + сделаноХодов + ' ходов ботом');

  // Пункт (6): обратное покрытие g -> VIEW_FIELDS по объединению ключей
  // за оба состояния (свежая партия даёт «startRolls», ход-другой при
  // удаче даёт «resume» — но даже если resume так и не появился, это
  // просто предупреждение ниже, не повод молчать про лишние ключи).
  console.log('');
  console.log('--- Обратное покрытие: у g нет верхних полей вне VIEW_FIELDS (кроме seed/decks) ---');
  console.log('Ключи g, встреченные за прогон: ' + Array.from(накопленныеКлючиG).sort().join(', '));

  const множествоVIEW = new Set(списокПолей);
  const лишниеКлючи = Array.from(накопленныеКлючиG)
    .filter((k) => k !== 'seed' && k !== 'decks' && !множествоVIEW.has(k))
    .sort();
  шаг(
    лишниеКлючи.length === 0,
    'все верхние ключи g за прогон (кроме seed/decks) входят в VIEW_FIELDS' +
      (лишниеКлючи.length
        ? ' — ЛИШНИЕ (есть у g, забыты в списке, экран их не получит): ' + лишниеКлючи.join(', ')
        : ''),
  );

  for (const имя of списокПолей) {
    if (!накопленныеКлючиG.has(имя)) {
      console.log(
        'ВНИМАНИЕ (не провал) — поле VIEW_FIELDS «' + имя +
          '» ни разу не встретилось как ключ верхнего уровня g за весь прогон — возможно, список пора почистить',
      );
    }
  }
} catch (сбой) {
  шаг(false, 'розыгрыш партии и проверка view() отработали без исключения (поймано: ' + сбой.message + ')');
}

