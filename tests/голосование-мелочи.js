function создатьЭлемент(тег, реестр) {
  const классы = new Set();
  const слушатели = {};
  const атрибуты = {};
  let свойТекст = '';
  let _id = '';
  const эл = {
    tagName: тег.toUpperCase(), children: [], parentNode: null, disabled: false, offsetParent: {},
    classList: {
      add: function (к) { классы.add(к); },
      remove: function (к) { классы.delete(к); },
      contains: function (к) { return классы.has(к); },
      toggle: function (к, надо) {
        const нужно = надо === undefined ? !классы.has(к) : Boolean(надо);
        if (нужно) классы.add(к); else классы.delete(к);
      }
    },
    setAttribute: function (к, з) { атрибуты[к] = String(з); },
    getAttribute: function (к) { return (к in атрибуты) ? атрибуты[к] : null; },
    addEventListener: function (тип, fn) { (слушатели[тип] = слушатели[тип] || []).push(fn); },
    // Как в браузере: у выключенной кнопки нажатие не срабатывает.
    click: function () { if (эл.disabled) return; (слушатели.click || []).forEach(function (fn) { fn({}); }); },
    appendChild: function (реб) { return эл.insertBefore(реб, null); },
    insertBefore: function (реб, опорный) {
      if (реб.parentNode) {
        const старые = реб.parentNode.children;
        старые.splice(старые.indexOf(реб), 1);
      }
      const и = опорный ? эл.children.indexOf(опорный) : -1;
      if (и === -1) эл.children.push(реб); else эл.children.splice(и, 0, реб);
      реб.parentNode = эл;
      return реб;
    },
    contains: function (у) {
      for (let т = у; т; т = т.parentNode) if (т === эл) return true;
      return false;
    },
    querySelector: function (sel) { return найтиПоКлассу(эл, sel.replace(/^\./, '').split(':')[0]); },
    focus: function () {}
  };
  Object.defineProperty(эл, 'id', {
    get: function () { return _id; },
    set: function (з) { _id = з; реестр.set(з, эл); }
  });
  Object.defineProperty(эл, 'nextSibling', {
    get: function () {
      if (!эл.parentNode) return null;
      const с = эл.parentNode.children;
      return с[с.indexOf(эл) + 1] || null;
    }
  });
  Object.defineProperty(эл, 'textContent', {
    get: function () { return свойТекст + эл.children.map(function (р) { return р.textContent; }).join(''); },
    set: function (з) { эл.children.length = 0; свойТекст = String(з); }
  });
  return эл;
}

function найтиПоКлассу(корень, класс) {
  for (let i = 0; i < корень.children.length; i++) {
    const р = корень.children[i];
    if (р.classList.contains(класс)) return р;
    const в = найтиПоКлассу(р, класс);
    if (в) return в;
  }
  return null;
}

