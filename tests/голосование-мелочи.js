/* ---------- Б. Строка связи: «соперник» только на двоих ---------- */

/** Состояние стола на N мест; моё место — первое. */
function видСтола(сколько, какСписок) {
  const места = [];
  for (let i = 1; i <= сколько; i++) места.push({ номер: i, этоЯ: i === 1 });
  const вид = {
    этап: 'игра', код: КОД, версия: 1, номерСобытия: 1,
    соперникНаСвязи: true, соперникПришёл: true, яХожу: true, завершена: false
  };
  вид[какСписок || 'портреты'] = места;
  return вид;
}

/** Что страница скажет в строке связи: сразу после старта и позже. */
async function словаСвязи(сколько, какСписок) {
  const сеть = поднятьСеть(видСтола(сколько, какСписок));
  await сеть.сесть();
  const приветствие = сеть.тексты.length ? сеть.тексты[сеть.тексты.length - 1] : '';
  сеть.часы.сейчас += 5000;   // приветствие висит 4 секунды
  const второе = видСтола(сколько, какСписок);
  второе.версия = 2; второе.номерСобытия = 2;
  await сеть.новость(второе);
  const обычное = сеть.тексты.length ? сеть.тексты[сеть.тексты.length - 1] : '';
  return { приветствие: приветствие, обычное: обычное };
}

