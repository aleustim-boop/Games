/* ---------- поддельные часы и таймеры ---------- */

function создатьЧасы() {
  const ч = { сейчас: 1000000, таймеры: new Map(), след: 1 };
  ч.setTimeout = function (fn, мс) { const id = ч.след++; ч.таймеры.set(id, { fn: fn, когда: ч.сейчас + (мс || 0) }); return id; };
  ч.clearTimeout = function (id) { ч.таймеры.delete(id); };
  ч.шагнуть = function (мс) {
    const конец = ч.сейчас + мс;
    for (;;) {
      let ближний = null;
      ч.таймеры.forEach(function (т, id) { if (т.когда <= конец && (!ближний || т.когда < ближний.т.когда)) ближний = { id: id, т: т }; });
      if (!ближний) break;
      ч.таймеры.delete(ближний.id);
      ч.сейчас = ближний.т.когда;
      ближний.т.fn();
    }
    ч.сейчас = конец;
  };
  return ч;
}

