/* Пауза сервера в песочнице: с запасом больше любой проверяемой (до 10 минут). */
const ПАУЗА_СЕРВЕРА_МС = 600000;
const ФАЙЛ_СЕРВЕРА = path.join(КОРЕНЬ, 'server', 'комнаты.js');

/** Вырезать из текста целую функцию верхнего уровня: от «function имя(» до первой «\n}\n». */
function вырезатьФункцию(исходник, имя) {
  const от = исходник.indexOf('\nfunction ' + имя + '(');
  if (от === -1) throw new Error('в server/комнаты.js не найдена функция «' + имя + '» — проверка слепа');
  const конец = /\r?\n\}\r?\n/g;
  конец.lastIndex = от;
  const н = конец.exec(исходник);
  if (!н) throw new Error('у функции «' + имя + '» не найден конец');
  return исходник.slice(от, н.index + н[0].length);
}

/** Сервер выполняется в песочнице только в части этих двух функций — сам сервер не запускается. */
function собратьСерверныеСлова() {
  const исходник = fs.readFileSync(довод('--сервер') || ФАЙЛ_СЕРВЕРА, 'utf8');
  const код = вырезатьФункцию(исходник, 'числоСоСловом') + вырезатьФункцию(исходник, 'почемуРаноПредлагать') +
    '\nglobalThis.__слова = function (секунд) {' +
    ' return почемуРаноПредлагать({ игроки: { 1: { предлагалЗакончить: 1 } } }, 1, 1 + паузаМеждуПредложениями - секунд * 1000); };';
  const песок = { Math: Math, паузаМеждуПредложениями: ПАУЗА_СЕРВЕРА_МС };
  vm.runInNewContext(код, песок, { filename: ФАЙЛ_СЕРВЕРА });
  return песок.__слова;
}

const СЛОВА_СЕРВЕРА = собратьСерверныеСлова();

/** Что сервер скажет игроку, которому до новой попытки осталось столько секунд. */
function фразаСервера(секунд) {
  const отказ = СЛОВА_СЕРВЕРА(секунд);
  if (!отказ || отказ.принято !== false || typeof отказ.причина !== 'string' || !отказ.причина) {
    throw new Error('сервер не дал слов отказа на ' + секунд + ' сек. — проверка слепа');
  }
  return отказ.причина;
}

