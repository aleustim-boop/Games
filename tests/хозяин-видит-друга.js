  await пауза(5000);
  const столПослеВхода = await прочитатьСтол(хозяин);
  console.log('  стол хозяина через 5с после входа друга: ' + JSON.stringify(столПослеВхода.map((м) => м.подпись)));

  const живойНаМесте = столПослеВхода.some((м, i) => {
    const былоСвободно = столДоВхода[i] && столДоВхода[i].подпись === 'Свободно';
    const сталоЗанято = м.подпись !== 'Свободно' && м.классы.indexOf('рассадка__место--бот') === -1 && м.классы.indexOf('--я') === -1;
    return былоСвободно && сталоЗанято;
  });

  const опросыПослеВхода = запросыХозяинаКОпросу.filter((з) => з.время >= меткаВхода - 200);
  console.log('  опросов хозяина «/что-нового» после входа друга: ' + опросыПослеВхода.length);
  console.log('  живой игрок появился на месте у хозяина: ' + живойНаМесте);

  const снимок = path.join(__dirname, 'снимки', 'застывший-хозяин-' + вариант.имя + '.png');
  await хозяин.screenshot({ path: снимок });
  console.log('  снимок хозяина: ' + снимок);

  const ошибкиХозяина = журналХозяина.filter((з) => з.тип === 'error' || з.тип === 'pageerror' || з.тип.indexOf('http-') === 0);
