/** Запрос к копии сервера комнат — так же, как ходил бы браузер. */
function запрос(путь, тело) {
  return new Promise(function (готово, беда) {
    const текст = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const о = http.request({
      host: '127.0.0.1', port: Number(ПОРТ_СЕРВЕРА), method: 'POST', path: encodeURI(путь),
      headers: { 'Content-Type': 'application/json', 'Content-Length': текст.length }
    }, function (ответ) {
      let к = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (ч) { к += ч; });
      ответ.on('end', function () { try { готово(JSON.parse(к)); } catch (сбой) { готово({}); } });
    });
    о.on('error', беда);
    о.end(текст);
  });
}

/** Подписаться на все console-сообщения и pageerror страницы. */
function следитьЗаКонсолью(страница, метка, журнал) {
  страница.on('console', (m) => {
    журнал.push({ кто: метка, тип: m.type(), текст: m.text() });
  });
  страница.on('pageerror', (e) => {
    журнал.push({ кто: метка, тип: 'pageerror', текст: e.message, стек: e.stack });
  });
}

/** Прочитать состояние стола хозяина: кто на каком месте и как выглядит. */
async function прочитатьСтол(страница) {
  return страница.evaluate(() => {
    return Array.from(document.querySelectorAll('#комната-стол .рассадка__место')).map((у) => ({
      подпись: у.getAttribute('aria-label') || '',
      классы: у.className
    }));
  });
}

