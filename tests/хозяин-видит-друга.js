  if (вариант.вФон) {
    console.log('  хозяин уводит вкладку в фон (visibilitychange hidden)');
    await хозяин.evaluate(() => {
      Object.defineProperty(document, 'hidden', { value: true, configurable: true });
      Object.defineProperty(document, 'visibilityState', { value: 'hidden', configurable: true });
      document.dispatchEvent(new Event('visibilitychange'));
    });
    await пауза(1500);
    console.log('  хозяин возвращает вкладку из фона (visibilitychange visible)');
    await хозяин.evaluate(() => {
      Object.defineProperty(document, 'hidden', { value: false, configurable: true });
      Object.defineProperty(document, 'visibilityState', { value: 'visible', configurable: true });
      document.dispatchEvent(new Event('visibilitychange'));
    });
    await пауза(500);
  }

  const столДоВхода = await прочитатьСтол(хозяин);
  console.log('  стол хозяина до входа друга: ' + JSON.stringify(столДоВхода.map((м) => м.подпись)));

  // --- Друг входит по коду — обычным HTTP-запросом, без второго браузера ---
  const меткаВхода = Date.now();
  const вход = await запрос('/войти', { код: код, имя: 'Подруга' });
  console.log('  друг вошёл запросом «/войти» в ' + меткаВхода + ': ' + JSON.stringify(вход));

