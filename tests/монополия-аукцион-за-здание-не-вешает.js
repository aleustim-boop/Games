const path = require('node:path');

const КОРЕНЬ = path.join(__dirname, '..');
const ПУТЬ_ПРАВИЛ = process.argv[2] || path.join(КОРЕНЬ, 'js', 'монополия-правила.js');
const ИСПОЛЬЗУЕТСЯ_КОПИЯ = Boolean(process.argv[2]);
const P = require(ПУТЬ_ПРАВИЛ);

let проверок = 0;
let провалов = 0;
function отметить(условие, текст) {
  проверок++;
  if (условие) {
    console.log('ок — ' + текст);
  } else {
    провалов++;
    console.log('ПЛОХО — ' + текст);
  }
  return условие;
}

// Сообщения отказов, которые могут случиться ДО того, как код дойдёт
// до нужной нам ветки про последний дом банка. Если попытка построить
// упала на одно из них — это значит, что раскладка моего теста сама
// сломана, а не что я поймал искомый баг.
const ПОСТОРОННИЕ_ОТКАЗЫ = [
  'Это не ваша собственность',
  'Стройте равномерно',
  'В банке закончились здания',
  'Не хватает денег',
  'Сначала другой игрок должен оплатить долг',
  'Сначала завершите текущее действие',
];

const own = (g, p, ids, level = 0) =>
  ids.forEach((id) => Object.assign(g.properties[id], { owner: p, level }));

/* Общий стол для обоих сценариев: у каждого из трёх игроков — своя
   целая ровная застройка (можно строить следующий дом), а в банке
   остаётся ровно один дом. */
function базовыйСтол(seed) {
  const g = P.create(3, seed);
  g.turn = 0; // ходит А
  own(g, 0, [16, 18, 19], 0); // квартал А (оранжевый)
  own(g, 1, [6, 8, 9], 0); // квартал Б (голубой)
  own(g, 2, [11, 13, 14], 0); // квартал В (розовый)
  // Заполнители: съедают запас домов банка, чей это «квартал» — не
  // важно для stock(), она считает по всем клеткам подряд.
  [21, 23, 24].forEach((id) => {
    g.properties[id].level = 4;
  });
  [26, 27, 29].forEach((id) => {
    g.properties[id].level = 4;
  });
  g.properties[37].level = 4;
  g.properties[39].level = 3;
  return g;
}

function проверитьРаскладку(g, название) {
  отметить(P.stock(g).houses === 1, название + ': в банке остался ровно 1 дом');
  отметить(P.buildable(g, 0, 16), название + ': игрок А может построить свой следующий дом');
  отметить(P.buildable(g, 1, 6), название + ': игрок Б может построить свой следующий дом');
  отметить(P.buildable(g, 2, 11), название + ': игрок В может построить свой следующий дом');
}

/* Попытка построить последний дом банка. Отказ (исключение) — это
   ожидаемый исход (А), не ошибка теста. */
function попытатьсяПостроить(g, игрок, id) {
  try {
    P.action(g, игрок, { type: 'build', id });
    return { исключение: null };
  } catch (e) {
    return { исключение: e };
  }
}

/* Доводит начавшийся аукцион за здание до конца: все, кому он
   предложен, по очереди пасуют — этого достаточно, чтобы аукцион
   завершился (никто не выиграл, дом остаётся в банке). */
function довестиАукционДоКонца(g, название) {
  let шагов = 0;
  while (g.phase === 'auction' && шагов++ < 20) {
    const актёр = P.who(g);
    P.action(g, актёр, { type: 'pass' });
  }
  отметить(g.phase !== 'auction', название + ': аукцион за здание завершился (не завис)');
}

/* Общая часть сценария: попытка построить последний дом, разбор
   исхода (А/Б/непредвиденный третий), проверка что игра не зависла
   с пустой очередью, проверка что who(g) не падает. */
function пройтиПопыткуПостройки(g, название, строитель, id) {
  const этапДо = g.phase;
  const очередьДоJSON = JSON.stringify(g.queue);

  const { исключение } = попытатьсяПостроить(g, строитель, id);

  if (исключение) {
    const постороннийОтказ = ПОСТОРОННИЕ_ОТКАЗЫ.some((кусок) => исключение.message.includes(кусок));
    отметить(
      !постороннийОтказ,
      название + ': отказ по делу, не по посторонней причине (сообщение: «' + исключение.message + '»)',
    );
    отметить(g.phase === этапДо, название + ': исход (А) — этап после отказа не сдвинулся (' + g.phase + ')');
    отметить(
      JSON.stringify(g.queue) === очередьДоJSON,
      название + ': исход (А) — очередь дел после отказа не тронута',
    );
  } else if (g.phase === 'auction') {
    отметить(true, название + ': исход (Б) — вместо отказа начался честный аукцион за здание');
    довестиАукционДоКонца(g, название);
  } else {
    отметить(
      false,
      название + ': последний дом банка ушёл БЕЗ отказа и БЕЗ аукциона, хотя строить могут минимум двое',
    );
  }

  const зависла = ['buy', 'debt'].includes(g.phase) && g.queue.length === 0;
  отметить(!зависла, название + ': игра не встала в этапе «' + g.phase + '» с пустой очередью дел');

  let упалоНаКто = null;
  try {
    P.who(g);
  } catch (e) {
    упалоНаКто = e;
  }
  отметить(
    !упалоНаКто,
    название + ': определение «чей ход» (who) не падает исключением' + (упалоНаКто ? ' (упало: ' + упалоНаКто.message + ')' : ''),
  );
}

/* Ищет среди последних событий партии такое, у которого совпадает
   kind (и, если задано, остальные поля из доп). */
function найтиСобытие(g, kind, доп = {}) {
  return g.events.find(
    (e) => e.kind === kind && Object.keys(доп).every((ключ) => e[ключ] === доп[ключ]),
  );
}

/* Стол для сценариев 3 и 4: честный аукцион за последний дом банка
   (стартует из этапа «manage» — тут отказа быть не должно, аукцион
   заводится по-настоящему). А — инициатор, просто пасует. У Б и В —
   свои кварталы на уровне 1 (уже по домику на каждой клетке), так что
   каждый может достроить ещё один дом. Когда бРовно=false, у Б,
   как и у В, застройка «хрупкая»: после ставки он продаст один дом
   в своём квартале и тем самым испортит собственную цель. */
function столДляАукциона(seed, бРовно) {
  const g = P.create(3, seed);
  g.turn = 0;
  g.phase = 'manage';
  g.queue = [];
  own(g, 0, [16, 18, 19], 0); // А — инициатор, свой дом не достраивает
  own(g, 1, [6, 8, 9], бРовно ? 0 : 1); // Б
  own(g, 2, [11, 13, 14], 1); // В — всегда «хрупкий», продаст себе дом
  // Заполнители банка (владелец не важен — stock() считает по всем клеткам).
  [21, 23, 24].forEach((id) => {
    g.properties[id].level = 4;
  });
  [26, 27, 29].forEach((id) => {
    g.properties[id].level = 4;
  });
  if (бРовно) {
    g.properties[37].level = 2;
    g.properties[39].level = 2;
  } else {
    g.properties[37].level = 1;
    g.properties[39].level = 0;
  }
  return g;
}

