/* Поднять экран монополии с заданной памятью; вернуть узлы и память. */
function запустить(источник, память, правила) {
  const документ = Браузер.сделатьДокумент();
  const создатьУзел = документ.createElement;
  // classList.replace есть в браузере, в общей подделке его нет — экран им пользуется
  документ.createElement = function (тег) {
    const у = создатьУзел(тег);
    у.classList.replace = function (было, стало) { у.classList.remove(было); у.classList.add(стало); };
    return у;
  };
  const узлы = Object.create(null);
  const заведён = (id, класс, родитель) => {
    const у = документ.createElement('div');
    у.id = id;
    у.className = класс || '';
    (родитель || документ.body).appendChild(у);
    узлы[id] = у;
    return у;
  };
  const лобби = заведён('экран-лобби', 'экран экран--виден mono-lobby');
  for (const id of ['mono-restore-note', 'mono-resume', 'mono-error']) {
    const описание = узелИзРазметки(источник.страница, id);
    // Узла нет в разметке — экран сам его не найдёт; у настоящей страницы это ошибка при открытии.
    if (описание) заведён(id, описание.класс, описание.вЛобби ? лобби : undefined);
  }
  // Остальное экран находит по id — заводим по первому обращению.
  const настоящий = документ.getElementById;
  документ.getElementById = function (id) {
    return настоящий(id) || заведён(id, '');
  };
  документ.__заготовки = { P: правила || P, Д };
  const заготовка =
    'var crypto = { getRandomValues: function (а) { а[0] = 12345; return а; } };' + // новая партия берёт зерно из crypto

    'window.МонополияПравила = document.__заготовки.P;' +
    'window.МонополияДанные = document.__заготовки.Д;' +
    'window.МонополияБот = {}; window.МонополияПоле = {};' +
    'window.ЛистЕщё = { подключить: function () { return { открыть: function () {} }; } };\n';
  const мир = Браузер.поднять(заготовка + источник.экран, {
    память,
    документ,
    имяФайла: 'js/монополия-экран.js',
  });
  return { мир, узлы, документ };
}

