/* Один раз заменить кусок в тексте; иначе — ошибка приёма порчи. */
function заменитьРовноОдин(текст, что, чем) {
  const частей = текст.split(что).length - 1;
  if (частей !== 1) throw new Error('приём порчи устарел: «' + что + '» найдено ' + частей + ' раз, ожидали 1');
  return текст.replace(что, чем);
}

function исходники() {
  let экран = fs.readFileSync(ЭКРАН, 'utf8');
  let страница = fs.readFileSync(СТРАНИЦА, 'utf8');
  if (ПАПКА_ПОРЧИ === null) return { экран, страница, копия: false };
  const вид = ВИДЫ_ПОРЧ[НОМЕР_ПОРЧИ - 1];
  if (!ПАПКА_ПОРЧИ || !вид) {
    throw new Error('нужно: --сломать <папка вне проекта> <номер 1..' + ВИДЫ_ПОРЧ.length + '> (' + ВИДЫ_ПОРЧ.map((в, и) => (и + 1) + ' ' + в).join(', ') + ')');
  }
  const папка = path.resolve(ПАПКА_ПОРЧИ);
  const отКорня = path.relative(КОРЕНЬ, папка);
  if (!отКорня.startsWith('..') && !path.isAbsolute(отКорня)) {
    throw new Error('папка порчи лежит внутри проекта: ' + папка + ' — нужна папка вне проекта');
  }
  if (вид === 'не-стирает') {
    экран = заменитьРовноОдин(экран, 'localStorage.removeItem(KEY);', '');
  } else if (вид === 'в-mono-error') {
    // Узел упомянут дважды: в показе слов (первый, его и портим) и в гашении (второй).
    const что = 'const заметка = $("mono-restore-note");';
    if (экран.split(что).length - 1 !== 2) throw new Error('приём порчи устарел: «' + что + '» найдено не 2 раза');
    экран = экран.replace(что, 'const заметка = $("mono-error");');
  } else if (вид === 'узла-нет') {
    const было = страница;
    страница = страница.replace(/^.*id="mono-restore-note".*\r?\n/m, '');
    if (страница === было) throw new Error('приём порчи устарел: узел mono-restore-note в странице не найден');
  } else if (вид === 'не-гасится') {
    экран = заменитьРовноОдин(экран, 'заметка.classList.add("скрыт");', '');
  } else if (вид === 'стирает-новую-версию') {
    // Как было бы без поправки: запись новее известной версии тоже считается негодной.
    экран = заменитьРовноОдин(экран, 'разобранная.version > ВЕРСИЯ_ЗАПИСИ', 'false');
  } else if (вид === 'стирать-на-любое') {
    // Как было до правки: при ошибке вне записи (правила не загрузились) запись тоже стирается.
    экран = заменитьРовноОдин(
      экран,
      '"Монополия: правила не загрузились — сохранённая партия не восстановлена и не стёрта.",',
      '"Монополия: правила не загрузились",\n    ); забытьНеподошедшуюПартию(');
  }
  fs.mkdirSync(папка, { recursive: true });
  fs.writeFileSync(path.join(папка, 'монополия-экран.js'), экран);
  fs.writeFileSync(path.join(папка, 'монополия.html'), страница);
  // Проверяем то, что реально лежит в копии на диске.
  экран = fs.readFileSync(path.join(папка, 'монополия-экран.js'), 'utf8');
  страница = fs.readFileSync(path.join(папка, 'монополия.html'), 'utf8');
  console.log('Ломающий запуск ' + НОМЕР_ПОРЧИ + ' «' + вид + '»: испорчена копия в ' + папка + ', файлы проекта не тронуты\n');
  return { экран, страница, копия: true };
}

/* Из настоящей разметки: класс узла по id и лежит ли он внутри лобби. */
function узелИзРазметки(страница, id) {
  const м = new RegExp('<(\\w+)[^>]*\\bid="' + id + '"[^>]*>').exec(страница);
  if (!м) return null;
  const класс = /\bclass="([^"]*)"/.exec(м[0]);
  const началоЛобби = страница.indexOf('<section id="экран-лобби"');
  const конецЛобби = началоЛобби === -1 ? -1 : страница.indexOf('</section>', началоЛобби);
  return {
    тег: м[1],
    класс: класс ? класс[1] : '',
    вЛобби: началоЛобби !== -1 && м.index > началоЛобби && м.index < конецЛобби,
  };
}

