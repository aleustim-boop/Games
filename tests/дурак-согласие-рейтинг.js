/* =====================================================================
   РЕЙТИНГ: ЗА СОПЕРНИКА «ВНЕ СЧЁТА» ОЧКОВ НЕ ПЛАТЯТ.

   Зачем. Партию можно закончить по согласию (голосованием). Тогда все,
   кто не сдавался, идут в рейтинг с пометкой «внеСчёта: true» (см.
   застольеДляРейтинга в server/комнаты.js): партию для рейтинга они не
   играли. Следующий этап (план штаб/план-дурак-согласие.md, Э2) оставит
   победу тому, кто в дураке успел скинуть карты. Без правки рейтинг
   заплатил бы ему по 10 очков за КАЖДОГО согласившегося — у них исход
   «не победил», и они выглядят обыгранными. Решение владельца: при
   согласии очки только за сдавшихся.

   ЧТО ПРОВЕРЯЕМ:
     1) A победил, B сдался, C и D вне счёта: у A партия и победа,
        очки только за B; у B партия без очков; у C и D записи нет;
     2) A победил, B, C, D вне счёта: у A партия и победа, очков 0;
        у B, C, D записи нет; сила с одним человеком в счёте не падает;
     3) бот вне счёта тоже не оплачивается;
     4) соперник вне счёта не отмечается в ограничителе сговора: после
        такой партии с C ещё все пять обычных партий с C идут в зачёт;
     5) обычный конец без «вне счёта» — очки прежние.

   Боевых данных не касается: папка данных (GAMES_DATA) — временная.

   УМЕЕТ КРАСНЕТЬ:
     node tests/дурак-согласие-рейтинг.js --сломать
       в КОПИИ server/рейтинг.js убирает пропуск соперника «вне счёта» —
       A снова берёт очки за C и D, прогон обязан провалиться.
   Копия server/ (без server/данные) и js/игры-реестр.js кладётся только
   во временную папку системы. Файлы проекта не трогаются.

   Запуск: node tests/дурак-согласие-рейтинг.js
   Выход 0 — провалов нет.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

const ПРОЕКТ = path.join(__dirname, '..');
const ЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;

let всегоПроверок = 0;
let провалов = 0;
function равно(что, было, надо) {
  всегоПроверок++;
  if (было === надо) { console.log('  ок     ' + что + ': ' + было); return; }
  провалов++;
  console.log('  ПРОВАЛ ' + что + ': ' + было + ' (ждали ' + надо + ')');
}

/** Заменить ровно одно вхождение, иначе приём порчи устарел — сказать вслух. */
function заменитьРовноОдин(файл, старое, новое) {
  const части = fs.readFileSync(файл, 'utf8').split(старое);
  if (части.length !== 2) {
    throw new Error('приём порчи устарел: «' + старое + '» встречается в ' + файл + ' ' +
      (части.length - 1) + ' раз(а) вместо одного — поправьте проверку тем же коммитом');
  }
  fs.writeFileSync(файл, части.join(новое), 'utf8');
}

/** Откуда брать код: из проекта или из испорченной копии во временной папке. */
function кодИзКопииИлиПроекта() {
  if (!ЛОМАТЬ) return ПРОЕКТ;
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'дурак-согласие-рейтинг-сломать-'));
  // Боевые данные в копию не везём — они не нужны и не наши.
  fs.cpSync(path.join(ПРОЕКТ, 'server'), path.join(папка, 'server'), {
    recursive: true,
    filter: function (откуда) {
      const имя = path.basename(откуда);
      return имя !== 'данные' && имя !== 'node_modules';
    }
  });
  fs.mkdirSync(path.join(папка, 'js'), { recursive: true });
  fs.copyFileSync(path.join(ПРОЕКТ, 'js', 'игры-реестр.js'), path.join(папка, 'js', 'игры-реестр.js'));
  // Порча: победителю снова платят и за тех, кто вне счёта.
  заменитьРовноОдин(path.join(папка, 'server', 'рейтинг.js'),
    'if (другой && другой.внеСчёта === true) continue;',
    '/* ИСПОРЧЕНО --сломать: за соперника вне счёта снова платят */');
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: код из испорченной копии ' + папка +
    ' — прогон обязан провалиться ***\n');
  return папка;
}

const КОД = кодИзКопииИлиПроекта();
process.env.GAMES_DATA = fs.mkdtempSync(path.join(os.tmpdir(), 'дурак-согласие-рейтинг-данные-'));
const рейтинг = require(path.join(КОД, 'server', 'рейтинг.js'));
const ЗА_ЧЕЛОВЕКА = рейтинг.ЦЕНА.человек;

/** Живой игрок за столом. исход: 'победа' | 'поражение' | 'ничья' | 'вне счёта'. */
function человек(номер, исход) {
  return { номер: номер, имя: 'И' + номер, этоБот: false, парами: false, напарник: null,
    переводной: false, победил: исход === 'победа', ничья: исход === 'ничья',
    внеСчёта: исход === 'вне счёта' };
}
function бот(уровень, исход) {
  return { этоБот: true, уровень: уровень, победил: исход === 'победа', ничья: исход === 'ничья',
    внеСчёта: исход === 'вне счёта' };
}

/** Строка игрока в дурацкой таблице или null, если записи нет. */
function строкаИгрока(номер) {
  return рейтинг.срезДляИгрока('дурак', номер).я;
}
function поле(номер, имя) {
  const строка = строкаИгрока(номер);
  return строка ? строка[имя] : 'нет записи';
}
function естьЗапись(номер) {
  return строкаИгрока(номер) !== null;
}

console.log('=== Рейтинг: за соперника «вне счёта» очков не платят ===\n');

console.log('1. A победил, B сдался, C и D вне счёта');
рейтинг.забытьВсё();
const первая = рейтинг.учестьПартию('дурак', [
  человек(101, 'победа'), человек(102, 'поражение'),
  человек(103, 'вне счёта'), человек(104, 'вне счёта')
]);
равно('A: партий', поле(101, 'партий'), 1);
равно('A: побед', поле(101, 'побед'), 1);
равно('A: очки только за B', поле(101, 'очки'), ЗА_ЧЕЛОВЕКА.победа);
равно('A: ответ учестьПартию', первая[101], ЗА_ЧЕЛОВЕКА.победа);
равно('B: партий', поле(102, 'партий'), 1);
равно('B: побед', поле(102, 'побед'), 0);
равно('B: очки', поле(102, 'очки'), 0);
равно('C: записи нет', естьЗапись(103), false);
равно('D: записи нет', естьЗапись(104), false);
равно('в таблице двое', рейтинг.срезДляИгрока('дурак', 101).всего, 2);

console.log('\n2. A победил, B, C и D вне счёта');
рейтинг.забытьВсё();
const втораяОтвет = рейтинг.учестьПартию('дурак', [
  человек(201, 'победа'), человек(202, 'вне счёта'),
  человек(203, 'вне счёта'), человек(204, 'вне счёта')
]);
равно('A: партий', поле(201, 'партий'), 1);
равно('A: побед', поле(201, 'побед'), 1);
равно('A: очков 0', поле(201, 'очки'), 0);
равно('A: ответ учестьПартию', втораяОтвет[201], 0);
равно('B: записи нет', естьЗапись(202), false);
равно('C: записи нет', естьЗапись(203), false);
равно('D: записи нет', естьЗапись(204), false);
равно('в таблице один', рейтинг.срезДляИгрока('дурак', 201).всего, 1);

console.log('\n3. Бот вне счёта тоже не оплачивается');
рейтинг.забытьВсё();
рейтинг.учестьПартию('дурак', [
  человек(301, 'победа'), человек(302, 'поражение'), бот('сложный', 'вне счёта')
]);
равно('A: очки только за B, не за сложного бота', поле(301, 'очки'), ЗА_ЧЕЛОВЕКА.победа);

console.log('\n4. Вне счёта — не партия пары для ограничителя сговора');
рейтинг.забытьВсё();
// B — лёгкий бот: очков за него 0, поэтому счёт ниже — только за C.
рейтинг.учестьПартию('дурак', [
  человек(401, 'победа'), бот('лёгкий', 'поражение'), человек(403, 'вне счёта')
]);
let заПятьПартий = 0;
for (let i = 0; i < рейтинг.ПАРТИЙ_С_ОДНИМ_ЧЕЛОВЕКОМ_В_СУТКИ; i++) {
  заПятьПартий += рейтинг.учестьПартию('дурак', [человек(401, 'победа'), человек(403, 'поражение')])[401];
}
равно('A: все ' + рейтинг.ПАРТИЙ_С_ОДНИМ_ЧЕЛОВЕКОМ_В_СУТКИ + ' обычных партий с C в зачёте',
  заПятьПартий, ЗА_ЧЕЛОВЕКА.победа * рейтинг.ПАРТИЙ_С_ОДНИМ_ЧЕЛОВЕКОМ_В_СУТКИ);

console.log('\n5. Обычный конец без «вне счёта» — очки прежние');
рейтинг.забытьВсё();
рейтинг.учестьПартию('дурак', [
  человек(501, 'победа'), человек(502, 'победа'), человек(503, 'победа'), человек(504, 'поражение')
]);
равно('победитель 501 — за одного обыгранного', поле(501, 'очки'), ЗА_ЧЕЛОВЕКА.победа);
равно('проигравший 504', поле(504, 'очки'), 0);
равно('проигравший 504: партий', поле(504, 'партий'), 1);
рейтинг.учестьПартию('дурак', [человек(511, 'победа'), человек(512, 'поражение')]);
равно('вдвоём: победитель', поле(511, 'очки'), ЗА_ЧЕЛОВЕКА.победа);

console.log('\nИтого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
process.exit(провалов > 0 ? 1 : 0);
