/* Служебные поля партии не должны уходить игроку ни на каком уровне вложенности.
   Списка разрешённых ключей в модуле нет (вид собирается вручную), поэтому ловим именно их. */
const СЛУЖЕБНЫЕ = ['началоХода', 'просрочкаНаИтоге'];
function найтиСлужебные(значение, путь = 'вид', найдено = []) {
  if (значение && typeof значение === 'object') {
    for (const [ключ, v] of Object.entries(значение)) {
      if (СЛУЖЕБНЫЕ.includes(ключ)) найдено.push(путь + '.' + ключ);
      найтиСлужебные(v, путь + '.' + ключ, найдено);
    }
  }
  return найдено;
}

