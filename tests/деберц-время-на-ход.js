const новаяПартия = (мест, парами = false) => Д.раздать(null, { игроки: КЛЮЧИ.slice(0, мест), парами, цельДеберца: 301 });
const снимок = п => JSON.stringify(п.игра);
const номер = (п, ключ) => п.игроки.indexOf(ключ);

/* Ход человека «с экрана» — намерение, как его шлёт страница: пас (или первая
   масть, если пас запрещён), первая допустимая карта, «забрать», «раздача». */
function намерениеЗа(п, ключ) {
  const г = п.игра, i = номер(п, ключ);
  if (г.фаза === 'торговля') return { действие: 'торг', масть: П.обязанВыбрать(г) ? П.вариантыКозыря(г)[0] : null };
  if (г.фаза === 'игра') return { действие: 'карта', id: П.доступные(г, i)[0].id };
  return { действие: г.фаза === 'взятка' ? 'взятка' : 'раздача' };
}
function сходитьСам(п, ключ) { return Д.сделатьХод(п, ключ, намерениеЗа(п, ключ)); }

/* Довести партию просрочками до нужной фазы (ход делает бот, часы двигаем). */
function довестиДоФазы(п, фаза) {
  for (let шаг = 0; шаг < 3000 && п.игра.фаза !== фаза; шаг++) {
    assert.ok(!п.завершена, 'партия кончилась раньше фазы «' + фаза + '»');
    прожить(Д.СЕКУНД_НА_ХОД + 1);
    assert.ok(Д.ходПоПросрочке(п), 'просрочка ничего не сделала в фазе ' + п.игра.фаза);
  }
  assert.equal(п.игра.фаза, фаза, 'до фазы «' + фаза + '» не дошли');
}

/* Стол в нужной фазе, часы начаты с полной минуты. */
function столВФазе(режим, фаза) {
  const п = новаяПартия(режим.мест, режим.парами);
  довестиДоФазы(п, фаза);
  return п;
}

/* Ни одна карта, оставшаяся в руке просрочившего, не попала в вид соседа.
   Открытая карта и «фреза» видны всем — их не считаем. */
function рукаНеРаскрыта(п, просрочил) {
  const г = п.игра, i = номер(п, просрочил);
  const публичные = new Set([г.открытая && г.открытая.id, г.фреза && г.фреза.id]);
  const секретные = г.руки[i].filter(к => !публичные.has(к.id));
  assert.ok(секретные.length > 0, 'у просрочившего не осталось карт — проверять нечего');
  for (const ключ of п.игроки.filter(к => к !== просрочил)) {
    const текст = JSON.stringify(Д.видДляИгрока(п, ключ));
    const свои = new Set(г.руки[номер(п, ключ)].map(к => к.id));
    for (const к of секретные.filter(к => !свои.has(к.id))) {
      assert.ok(!текст.includes('"id":"' + к.id + '"'), 'карта ' + к.id + ' просрочившего ушла в вид соседа');
    }
  }
}

