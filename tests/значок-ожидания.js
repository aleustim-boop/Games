#!/usr/bin/env node
'use strict';

/* =====================================================================
   ПРОВЕРКА: «крутится кружочек», когда игра ждёт другого игрока.

   Три места, где человек видит слово «Ждём…», обязаны получить кружок-
   вертушку слева от надписи (владелец, 23.09: «должен крутить кружочек
   или три точки, которые двигаются»):
     — строка подсказки над кнопками хода (js/game.js, рисоватьПодсказку
       ИКнопки → класс «ожидание-крутится» на #подсказка-текст);
     — рамка серии на плашке итога партии, пока мы позвали на реванш
       и ждём ответа (js/game.js, написатьВРамкуИтога → тот же класс
       на #серия-итога);
     — кнопка «Начать» в комнате дурака, пока хозяин не начал (её класс
       «.комната__ожидает» ставит js/дурак-комната.js — файл чужой,
       здесь только смотрим на style.css).

   Кольцо везде — ОДНА И ТА ЖЕ анимация: keyframes у «.сеть-ожидание::before»
   (готовое кольцо, которое уже крутится на сетевом экране). Второй
   анимации в правилах для новых мест быть не должно — задание требует
   переиспользовать её, а не выдумывать заново.

   Проверка структурная (по тексту style.css и js/game.js), без браузера.
   «Ноль найденного» — это провал, а не пропуск: каждое утверждение падает
   явно, если селектор/вызов не нашёлся.

   ── Код выхода ──
   Обычный прогон (node tests/значок-ожидания.js):
     0 — все признаки на месте; 1 — чего-то не хватает (см. ✗ выше итога).

   Ломающий прогон (node tests/значок-ожидания.js --сломать <папка>):
     та же проверка гоняется по style.css и game.js, лежащим в <папка>
     (не по файлам проекта — их эта проверка не портит и не трогает).
     Портит копию сам исполнитель: скопировал style.css и js/game.js
     в свою временную папку, вручную вырезал проверяемое правило —
     и после этого прогон обязан вернуть код 1, иначе проверка дырявая.
   ===================================================================== */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.resolve(__dirname, '..');

const РЕЖИМ_ЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;
const ПУТЬ_ЛОМАНОЙ_ПАПКИ = РЕЖИМ_ЛОМАТЬ
  ? process.argv[process.argv.indexOf('--сломать') + 1]
  : null;

if (РЕЖИМ_ЛОМАТЬ && !ПУТЬ_ЛОМАНОЙ_ПАПКИ) {
  console.error('После --сломать нужен путь к папке с копиями style.css и game.js.');
  process.exit(1);
}

/** Ищет файл по списку возможных относительных имён внутри папки —
    так проверка находит game.js что рядом с style.css, что в подпапке js/. */
function найтиФайл(папка, имена) {
  for (const имя of имена) {
    const полный = path.join(папка, имя);
    if (fs.existsSync(полный)) return полный;
  }
  return null;
}

const путьStyle = РЕЖИМ_ЛОМАТЬ
  ? найтиФайл(ПУТЬ_ЛОМАНОЙ_ПАПКИ, ['style.css'])
  : path.join(КОРЕНЬ, 'style.css');
const путьGame = РЕЖИМ_ЛОМАТЬ
  ? найтиФайл(ПУТЬ_ЛОМАНОЙ_ПАПКИ, [path.join('js', 'game.js'), 'game.js'])
  : path.join(КОРЕНЬ, 'js', 'game.js');

let тестов = 0;
let провалов = 0;

function проверка(имя, дело) {
  тестов++;
  try {
    дело();
    console.log('✓ ' + имя);
  } catch (ошибка) {
    провалов++;
    console.error('✗ ' + имя);
    console.error('  ' + ошибка.message);
  }
}

function утверждение(условие, сообщение) {
  if (!условие) throw new Error(сообщение);
}

function итогИВыход() {
  console.log('\nИтого проверок: ' + тестов + ', провалов: ' + провалов);
  process.exit(провалов > 0 ? 1 : 0);
}

if (!путьStyle || !fs.existsSync(путьStyle)) {
  проверка('style.css найден', function () {
    утверждение(false, 'файл не найден: ' + (путьStyle || '(путь не собрался)'));
  });
  итогИВыход();
}
if (!путьGame || !fs.existsSync(путьGame)) {
  проверка('game.js найден', function () {
    утверждение(false, 'файл не найден: ' + (путьGame || '(путь не собрался)'));
  });
  итогИВыход();
}

const style = fs.readFileSync(путьStyle, 'utf8');
const game = fs.readFileSync(путьGame, 'utf8');

/** Вырезает сбалансированный блок { ... }, начиная с первой { после метки.
    Счётчик скобок, а не регулярка — \b в regex кириллицу не понимает. */
function вырезатьБлок(текст, метка) {
  const позицияМетки = текст.indexOf(метка);
  if (позицияМетки === -1) return null;
  const открывающая = текст.indexOf('{', позицияМетки);
  if (открывающая === -1) return null;
  let глубина = 0;
  for (let i = открывающая; i < текст.length; i++) {
    if (текст[i] === '{') глубина++;
    else if (текст[i] === '}') {
      глубина--;
      if (глубина === 0) return текст.slice(открывающая, i + 1);
    }
  }
  return null;
}

/** Все блоки CSS-правил, у которых в списке селекторов встречается данная
    подстрока (перед своей открывающей { — общей на весь список селекторов,
    как в блоке prefers-reduced-motion). Один селектор в файле часто встречается
    дважды: в самом правиле и в отключении анимации — нужны оба блока. */
function всеБлокиСелектора(текст, селектор) {
  const блоки = [];
  let от = 0;
  for (;;) {
    const индекс = текст.indexOf(селектор, от);
    if (индекс === -1) break;
    const открывающая = текст.indexOf('{', индекс);
    const закрывающая = открывающая === -1 ? -1 : текст.indexOf('}', открывающая);
    if (открывающая === -1 || закрывающая === -1) break;
    блоки.push(текст.slice(открывающая, закрывающая));
    от = закрывающая + 1;
  }
  return блоки;
}

/** Имя keyframes из свойства animation у правила с данным селектором —
    берём первый блок, где анимация настоящая (не «none» из reduced-motion). */
function имяНастоящегоKeyframes(текст, селектор) {
  const блоки = всеБлокиСелектора(текст, селектор);
  for (const блок of блоки) {
    const совпадение = блок.match(/animation:\s*([а-яА-ЯёЁ\-\w]+)/);
    if (совпадение && совпадение[1] !== 'none') return совпадение[1];
  }
  return null;
}

/* ---------- Эталон: кольцо «.сеть-ожидание», у него берём имя keyframes ---------- */

const эталонKeyframes = имяНастоящегоKeyframes(style, '.сеть-ожидание::before');
проверка('style.css: у «.сеть-ожидание::before» есть настоящая анимация (эталон для сравнения)', function () {
  утверждение(эталонKeyframes, 'в «.сеть-ожидание::before» не нашлось animation с именем keyframes — эталон сломан, сравнивать не с чем');
});
проверка('style.css: keyframes «' + эталонKeyframes + '» определён через @keyframes', function () {
  утверждение(эталонKeyframes && style.indexOf('@keyframes ' + эталонKeyframes) !== -1,
    'блок @keyframes ' + эталонKeyframes + ' не найден — имя есть, а самой анимации нет');
});

/* ---------- Подсказка и итог партии: класс «.ожидание-крутится» ---------- */

const keyframesОжидания = имяНастоящегоKeyframes(style, '.ожидание-крутится::before');
проверка('style.css: есть правило «.ожидание-крутится::before» с той же анимацией, что у «.сеть-ожидание»', function () {
  утверждение(keyframesОжидания,
    'правило .ожидание-крутится::before не найдено (или в нём нет animation) — подсказка и итог партии останутся без кружка');
  утверждение(keyframesОжидания === эталонKeyframes,
    '.ожидание-крутится::before использует другую анимацию («' + keyframesОжидания + '»), а не «' + эталонKeyframes + '»: задание просит ту же, не новую');
});

/* ---------- Кнопка «Начать» в комнате дурака: класс «.комната__ожидает» ---------- */

const keyframesКомнаты = имяНастоящегоKeyframes(style, '.комната__ожидает::before');
проверка('style.css: есть правило «.комната__ожидает::before» с той же анимацией, что у «.сеть-ожидание»', function () {
  утверждение(keyframesКомнаты,
    'правило .комната__ожидает::before не найдено (или в нём нет animation) — кнопка «Ожидаем игрока…» останется просто серой');
  утверждение(keyframesКомнаты === эталонKeyframes,
    '.комната__ожидает::before использует другую анимацию («' + keyframesКомнаты + '»), а не «' + эталонKeyframes + '»: задание просит ту же, не новую');
});

/* ---------- js/game.js: класс «ожидание-крутится» и ставится, и снимается ---------- */

function проверитьToggleВФункции(имяФункции, чтоРисует) {
  const тело = вырезатьБлок(game, 'function ' + имяФункции);
  проверка('game.js: функция ' + имяФункции + '() найдена и разбирается целиком', function () {
    утверждение(тело !== null, 'функция ' + имяФункции + ' не найдена или скобки не сбалансированы');
  });
  if (тело === null) return;

  проверка('game.js: ' + имяФункции + '() ставит и снимает класс «ожидание-крутится» на ' + чтоРисует, function () {
    const совпадение = тело.match(/classList\.toggle\('ожидание-крутится',\s*([^)]+)\)/);
    утверждение(совпадение !== null,
      'classList.toggle(\'ожидание-крутится\', ...) не найден внутри ' + имяФункции + ' — кружок над ' + чтоРисует + ' не появится');
    const довод = совпадение[1].trim();
    // Постоянная true/false — это класс, который либо всегда стоит, либо никогда
    // не появляется: тогда он не «ставится и снимается по тексту», а прибит гвоздями.
    утверждение(!/^(true|false)$/.test(довод),
      'второй довод toggle в ' + имяФункции + ' — застывшее ' + довод + ', а не условие: класс не будет сниматься, когда текст сменится на не-ожидание');
  });
}

проверитьToggleВФункции('рисоватьПодсказкуИКнопки', 'строкой подсказки');
проверитьToggleВФункции('написатьВРамкуИтога', 'рамкой итога партии');

итогИВыход();
