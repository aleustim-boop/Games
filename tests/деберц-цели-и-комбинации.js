function сДеберцем(цель, включён = true) {
  const и = П.создать(Math.random, цель, включён);
  const рука = [...П.ряд.slice(1).map(x => к(x)), к('7', '♦'), к('8', '♦')];
  const другая = [...П.ряд.map(x => к(x, '♥')), к('9', '♦')];
  const занято = new Set([...рука, ...другая, к('7')].map(x => x.id));
  Object.assign(и, { руки: [рука.slice(0, 6), другая.slice(0, 6)], открытая: к('7'),
    запас: [...рука.slice(6), ...другая.slice(6), ...П.масти.flatMap(м => П.ряд.map(x => к(x, м))).filter(x => !занято.has(x.id))] });
  return и;
}
