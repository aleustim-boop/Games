  проверить(м.отметитьПриход(5002, А, 'бот', 'дурак').почему === 'уже', 'после перезапуска повторно не привязать');
  проверить(м.партияСыграна(5002, СТОЛ).почему === 'уже', 'после перезапуска повторно не засчитать');
  проверить(м.партияСыграна(5001, СТОЛ).ок === true, 'после перезапуска ждущая привязка засчитывается');
  проверить(м.сводка().привязок === 3, 'после перезапуска привязок 3');

  // Битый файл
  const битая = новаяПапка();
  fs.writeFileSync(path.join(битая, 'привёл-друга.json'), '{нет такого json', 'utf8');
  м = свежийМодуль(битая);
  проверить(м.сводка().привязок === 0, 'битый файл — учёт начинается с чистого листа');
