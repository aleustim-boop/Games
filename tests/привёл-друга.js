  проверить(о3.итог.новыеНаграды.sort().join() === 'значок-друг-3,рубашка-друг', 'три друга — рубашка-друг и значок-друг-3');
  привестиИЗасчитать(м, 3004, Б);
  const о5 = привестиИЗасчитать(м, 3005, Б);
  проверить(о5.итог.новыеНаграды.join() === 'значок-друг-5', 'пять друзей — значок-друг-5');
  н = м.моиНаграды(Б);
  проверить(н.друзей === 5 && н.награды.length === 4 && н.следующая === null, 'на 5 друзьях все 4 награды, следующей ступени нет');
  проверить(о1.итог.наградыДругу.join() === 'рубашка-друг', 'партия сообщает награду другу — рубашка-друг');
  проверить(м.моиНаграды(3001).награды.join() === 'рубашка-друг' && м.моиНаграды(3001).друзей === 0,
    'засчитанный друг видит у себя рубашку-друг, но друзей у него 0');
  м = начать();
  м.отметитьПриход(3100, Б, 'бот', 'дурак');
  проверить(м.моиНаграды(3100).награды.length === 0, 'друг до первой засчитанной партии наград не имеет');

  // Сводка без номеров и кодов
  м = начать();
  const кодБ = м.кодПригласившего(Б);
  привестиИЗасчитать(м, 4001, Б);
  м.отметитьПриход(4002, Б, 'стол', 'шашки');
  м.отметитьПриход(4003, А, 'бот', 'дурак');
  const с = м.сводка(7);
  проверить(с.привязок === 3 && с.засчитано === 1 && с.ждут === 2 && с.пригласивших === 2, 'сводка: 3 привязки, 1 засчитан, 2 ждут, 2 пригласивших');
  const текст = JSON.stringify(с);
  const номера = ['1001', '1002', '4001', '4002', '4003', кодБ];
  проверить(номера.every(function (х) { return текст.indexOf(х) === -1; }), 'в сводке нет ни номеров Telegram, ни кодов');
  проверить(Object.keys(с).every(function (к) { return Number.isFinite(с[к]); }), 'в сводке только числа');
  часы += 10 * ДЕНЬ;
  проверить(м.сводка(7).привязок === 0 && м.сводка(0).привязок === 3, 'сводка за 7 дней не видит старого, «за всё» видит');

