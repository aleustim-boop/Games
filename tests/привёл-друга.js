  const папка = новаяПапка();
  часы = Date.parse('2026-10-03T12:00:00');
  м = свежийМодуль(папка);
  const кодВ = м.кодПригласившего(В);
  м.отметитьПриход(5001, В, 'стол', 'шашки');
