/* ---------------------------------------------------------------------
   Режим «сделать порчу»: копия модуля без одной строки-проверки.
   --------------------------------------------------------------------- */
function сделатьПорчу(вид, куда) {
  const метка = ПОРЧИ[вид];
  if (!метка) { console.error('Порча неизвестна: ' + вид); process.exit(2); }
  const строки = fs.readFileSync(МОДУЛЬ, 'utf8').split('\n');
  const оставить = строки.filter(function (с) { return с.indexOf('// ' + метка) === -1; });
  if (оставить.length === строки.length) {
    console.error('ПРОВАЛ: строка «' + метка + '» не найдена — нечего портить, проверка бы ничего не доказала');
    process.exit(2);
  }
  if (path.resolve(куда).toLowerCase().indexOf(path.resolve(path.join(__dirname, '..')).toLowerCase()) === 0) {
    console.error('Копию класть можно только вне проекта'); process.exit(2);
  }
  /* Копия лежит в другой папке: относительное подключение чинится на абсолютное. */
  const папка = ПАПКА_СЕРВЕРА.replace(/\\/g, '/');
  const текст = оставить.join('\n').replace(/require\('\.\/папка-данных\.js'\)/, "require(" + JSON.stringify(папка + '/папка-данных.js') + ")");
  fs.mkdirSync(path.dirname(path.resolve(куда)), { recursive: true });
  fs.writeFileSync(куда, текст, 'utf8');
  console.log('Копия с порчей «' + вид + '»: ' + куда);
  process.exit(0);
}

function запуститьСам(доводы) {
  return spawnSync(process.execPath, [__filename].concat(доводы), { encoding: 'utf8' });
}

function всеПорчи() {
  const корень = fs.mkdtempSync(path.join(os.tmpdir(), 'привёл-друга-порчи-'));
  let краснели = 0;
  const виды = Object.keys(ПОРЧИ);
  const чистый = запуститьСам([]);
  if (чистый.status !== 0) {
    console.log('ПРОВАЛ: на настоящем модуле проверка не зелёная');
    console.log(чистый.stdout + чистый.stderr);
    process.exit(1);
  }
  for (const вид of виды) {
    const копия = path.join(корень, 'привёл-друга-' + вид + '.js');
    const сделана = запуститьСам(['--сделать-порчу', вид, копия]);
    if (сделана.status !== 0) { console.log('ПРОВАЛ: порча «' + вид + '» не сделана: ' + сделана.stderr); process.exit(1); }
    const прогон = запуститьСам(['--сломать', копия]);
    const красный = прогон.status === 1;
    const провалов = (прогон.stdout.match(/^ПРОВАЛ:/gm) || []).length;
    console.log((красный ? 'покраснела' : 'НЕ ПОКРАСНЕЛА') + ' на порче «' + вид + '» (провалов: ' + провалов + ')');
    if (красный && провалов > 0) краснели++;
  }
  console.log('Порч покраснело: ' + краснели + ' из ' + виды.length);
  process.exit(краснели === виды.length ? 0 : 1);
}

const номерСломать = аргументы.indexOf('--сломать');
if (аргументы[0] === '--сделать-порчу') сделатьПорчу(аргументы[1], аргументы[2]);
