/** Свежая копия модуля на своей папке данных. Все проверки — на ней. */
function свежийМодуль(папка, внешнее) {
  process.env.ДАННЫЕ_ИГРЫ = папка;
  for (const ключ of Object.keys(require.cache)) {
    if (ключ === ПУТЬ_МОДУЛЯ || ключ.indexOf('папка-данных.js') !== -1) delete require.cache[ключ];
  }
  const модуль = require(ПУТЬ_МОДУЛЯ);
  /* По умолчанию «играл ли» подключено и отвечает «нет»: без неё привязки не даются. */
  модуль.подключить(Object.assign({
    сейчас: function () { return часы; },
    игралРаньше: function () { return false; }
  }, внешнее || {}));
  модуль.включитьЗапись();
  return модуль;
}

function новаяПапка() {
  const папка = path.join(корневаяПапка, 'п' + (++счётчикПапок));
  fs.mkdirSync(папка, { recursive: true });
  return папка;
}

function начать(внешнее) {
  часы = Date.parse('2026-10-03T12:00:00');
  return свежийМодуль(новаяПапка(), внешнее);
}

/** Привязать и засчитать одного друга одним вызовом. */
function привестиИЗасчитать(м, друг, кто) {
  const привязка = м.отметитьПриход(друг, кто, 'бот', 'дурак');
  const итог = м.партияСыграна(друг, { игра: 'дурак', вид: 'стол', когда: часы });
  return { привязка: привязка, итог: итог };
}

