function собратьОшибки(страница) {
  const ошибки = [];
  страница.on('pageerror', function (о) { ошибки.push('исключение: ' + о.message); });
  страница.on('console', function (с) {
    if (с.type() !== 'error') return;
    if (/Failed to load resource/.test(с.text())) return;
    ошибки.push('консоль: ' + с.text());
  });
  return ошибки;
}

async function дождатьсяЭкрана(страница, id, мс) {
  try {
    await страница.waitForFunction(function (и) {
      const э = document.getElementById(и);
      return Boolean(э && э.classList.contains('экран--виден'));
    }, id, { timeout: мс || 6000 });
    return true;
  } catch (сбой) { return false; }
}

async function замерыПрофиля(страница) {
  return страница.evaluate(function () {
    function числоИзТекста(т) {
      const с = String(т == null ? '' : т).replace(/[^0-9-]/g, '');
      const н = parseInt(с, 10);
      return isNaN(н) ? null : н;
    }
    const р = { найдено: {} };
    const эк = document.getElementById('экран-профиля-игрока');
    р.найдено.экран = Boolean(эк);
    if (!эк) return р;

    const карточка = document.getElementById('профиль-карточка');
    р.найдено.карточка = Boolean(карточка);
    if (карточка) {
      const иниц = карточка.querySelector('.профиль-карточка__инициалы');
      const фото = карточка.querySelector('.профиль-карточка__аватар--фото');
      р.найдено.аватар = Boolean((иниц && иниц.textContent.trim()) || фото);
      const имя = карточка.querySelector('.профиль-карточка__имя');
      р.имя = имя ? имя.textContent.trim() : '';
      const место = карточка.querySelector('.профиль-карточка__место');
      р.место = место ? место.textContent.trim() : '';
      const очки = карточка.querySelector('.профиль-карточка__очки');
      р.очкиТекст = очки ? очки.textContent.trim() : '';
    }

    const заголовок = эк.querySelector('.профиль-очки__заголовок');
    р.найдено.заголовокОчков = Boolean(заголовок) && /Ваши очки по играм/.test(заголовок.textContent || '');

    const строкиУзлы = Array.prototype.slice.call(эк.querySelectorAll('.профиль-очки__строка'));
    р.найдено.строкОчков = строкиУзлы.length;
    р.строки = строкиУзлы.map(function (с) {
      const числоУзел = с.querySelector('.профиль-очки__число');
      return { игра: с.getAttribute('data-игра'), число: числоИзТекста(числоУзел ? числоУзел.textContent : '') };
    });

    const итогПодпись = эк.querySelector('.профиль-очки__итог-подпись');
    const итогЧисло = эк.querySelector('.профиль-очки__итог-число');
    р.найдено.итог = Boolean(итогПодпись) && Boolean(итогЧисло);
    р.итогПодпись = итогПодпись ? итогПодпись.textContent.trim() : '';
    р.итогЧисло = числоИзТекста(итогЧисло ? итогЧисло.textContent : '');

    const кнопкаКакЯИграю = document.getElementById('кнопка-профиля-как-я-играю');
    р.найдено.кнопкаКакЯИграю = Boolean(кнопкаКакЯИграю) && (кнопкаКакЯИграю.textContent || '').trim() === 'Как я играю';

    const кнопкаНазад = document.getElementById('кнопка-профиля-назад');
    р.найдено.кнопкаНазад = Boolean(кнопкаНазад);
    р.назадВидна = Boolean(кнопкаНазад) && кнопкаНазад.offsetParent !== null;

    р.scrollWidthDoc = document.documentElement.scrollWidth;
    р.innerWidth = window.innerWidth;
    р.классХтмл = document.documentElement.className;
    р.одинВидимыйЭкран = document.querySelectorAll('.экран.экран--виден').length;

    return р;
  });
}

async function замерНиза(страница) {
  return страница.evaluate(function () {
    const эк = document.getElementById('экран-профиля-игрока');
    if (!эк) return { найден: false };
    const cs = getComputedStyle(эк);
    const overflowY = cs.overflowY;
    const paddingBottomPx = parseFloat(cs.paddingBottom) || 0;
    эк.scrollTop = эк.scrollHeight;
    const nav = эк.querySelector('.нижние-вкладки');
    const navTop = nav ? nav.getBoundingClientRect().top : null;
    const дети = Array.prototype.slice.call(эк.children).filter(function (д) {
      return д.offsetParent !== null && !д.classList.contains('нижние-вкладки');
    });
    let низ = null;
    дети.forEach(function (д) {
      const r = д.getBoundingClientRect();
      if (низ === null || r.bottom > низ) низ = r.bottom;
    });
    return { найден: true, overflowY: overflowY, paddingBottomPx: paddingBottomPx, navTop: navTop, низ: низ };
  });
}

