/** Раздача файлов проекта на свободном порту; «подмены» — карта {url-путь: файл-на-диске}. */
function поднятьРаздачу(подмены) {
  const карта = подмены || {};
  const сервер = http.createServer(function (запрос, ответ) {
    let путь = запрос.url.split('?')[0].split('#')[0];
    try { путь = decodeURIComponent(путь); } catch (ошибка) { /* оставим как есть */ }
    const файл = карта[путь] || path.join(КОРЕНЬ, путь === '/' ? 'index.html' : путь.slice(1));
    fs.readFile(файл, function (беда, тело) {
      if (беда) { ответ.writeHead(404); ответ.end('нет такого файла'); return; }
      ответ.writeHead(200, { 'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'text/plain' });
      ответ.end(тело);
    });
  });
  return new Promise(function (готово) { сервер.listen(0, '127.0.0.1', function () { готово(сервер); }); });
}

/** Заменить фрагмент в исходнике и сохранить испорченную копию во временной папке (файл проекта не трогаем). */
function испортитьКопию(относительныйПуть, было, стало, префикс) {
  const путьКФайлу = path.join(КОРЕНЬ, относительныйПуть);
  const исходник = fs.readFileSync(путьКФайлу, 'utf8');
  if (исходник.indexOf(было) === -1) {
    console.error('ломающий запуск сломался: в ' + относительныйПуть + ' не нашёлся ожидаемый фрагмент — ' +
      'ноль замен, портить нечего (провал, а не пропуск)');
    process.exit(2);
  }
  const испорченный = исходник.split(было).join(стало);
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), префикс + '-'));
  const копия = path.join(папка, path.basename(относительныйПуть));
  fs.writeFileSync(копия, испорченный, 'utf8');
  console.log('испорченная копия ' + относительныйПуть + ' лежит в ' + копия);
  return копия;
}

