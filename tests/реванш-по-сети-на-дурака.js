'use strict';

/* =====================================================================
   РЕВАНШ ПО СЕТИ: ходят ли на дурака ЧЕРЕЗ НАСТОЯЩИЙ СЕРВЕР.

   Зачем отдельная проверка. Правило первого хода живёт в js/game.js, и его
   уже проверяет tests/первый-ход-на-дурака.js — но там правила зовут прямо
   из файла. А в жизни между правилами и игроком стоит СЕРВЕР КОМНАТ: он
   запоминает дурака, он же раздаёт карты на реванше. Если сервер запущен
   со старым кодом или забыл дурака, игрок увидит ровно ту беду, на которую
   жаловался владелец, — «я проиграл, а хожу опять я».

   ИМЕННО ЭТО И СЛУЧИЛОСЬ при первой проверке: сервер на порту 8790 был
   поднят раньше правок и играл по старому правилу. Числами это видно
   только так — через живой сервер, а не через файл на диске.

   Что делает файл. Создаёт комнату, сажает ботов, доигрывает партию
   до конца, зовёт реванш и смотрит: кто нападает и кто отбивается.
   Ждём одного — отбивается дурак прошлой партии, нападает его сосед
   по кругу (тот, кто сидит прямо ПЕРЕД ним). После ничьей правило
   не работает: там решает младший козырь, и мы просто не придираемся.

   Запуск (сервер комнат уже поднят):
       node tests/реванш-по-сети-на-дурака.js               порт 8790, стол на 4, 6 партий
       node tests/реванш-по-сети-на-дурака.js 8791 6 10     свой порт, стол, число партий

   Код возврата: 0 — правило соблюдено, 1 — нарушено или партия не доигралась.
   ===================================================================== */

const http = require('http');

const ПОРТ = Number(process.argv[2]) || 8790;
const МЕСТ = Number(process.argv[3]) || 4;
const ПАРТИЙ = Number(process.argv[4]) || 6;
const ХОЗЯИН = '127.0.0.1';
const ПРЕДЕЛ_ШАГОВ = 6000;      // защита от вечного ожидания

function спросить(путь, тело) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (ч) { текст += ч; });
      ответ.on('end', function () {
        try { готово({ код: ответ.statusCode, тело: JSON.parse(текст || '{}') }); }
        catch (е) { готово({ код: ответ.statusCode, тело: { сырое: текст } }); }
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

const спать = function (мс) { return new Promise(function (f) { setTimeout(f, мс); }); };

/** Состояние стола глазами хозяина комнаты. */
async function состояние(код, пропуск) {
  const о = await спросить('/состояние', { код: код, пропуск: пропуск });
  return (о.тело && о.тело.состояние) || {};
}

/** Кто сидит прямо перед этим местом по кругу. */
function соседПеред(застолом, номер) {
  const номера = застолом.map(function (м) { return м.номер; });
  const i = номера.indexOf(номер);
  return номера[(i - 1 + номера.length) % номера.length];
}

function имяМеста(застолом, номер) {
  const м = застолом.filter(function (x) { return x.номер === номер; })[0];
  return м ? м.имя + ' (место ' + номер + ')' : 'место ' + номер;
}

let провалов = 0;
function проверить(условие, что) {
  if (!условие) { провалов++; console.log('  ПРОВАЛ: ' + что); }
}

/** Один любой законный ход за себя: положить, отбить или сказать слово. */
async function походитьЗаСебя(код, пропуск, вид) {
  const рука = вид.мояРука || [];
  for (let к = 0; к < рука.length; к++) {
    if (вид.яОтбиваюсь) {
      for (let пара = 0; пара < (вид.стол || []).length; пара++) {
        const о = await спросить('/ход', { код: код, пропуск: пропуск, действие: 'отбить', карта: к, пара: пара });
        if (о.тело && о.тело.принято) return true;
      }
    } else {
      const о = await спросить('/ход', { код: код, пропуск: пропуск, действие: 'ходить', карта: к });
      if (о.тело && о.тело.принято) return true;
    }
  }
  for (const слово of ['беру', 'бито']) {
    const о = await спросить('/ход', { код: код, пропуск: пропуск, действие: слово });
    if (о.тело && о.тело.принято) return true;
  }
  return false;
}

(async function () {
  console.log('=== Реванш по сети: ходят ли на дурака ===');
  console.log('сервер: http://' + ХОЗЯИН + ':' + ПОРТ + ', мест за столом ' + МЕСТ +
              ', партий подряд ' + ПАРТИЙ + '\n');

  const создано = await спросить('/создать', { игроки: МЕСТ });
  if (!создано.тело || !создано.тело.код) {
    console.log('Комнату создать не вышло: ' + JSON.stringify(создано.тело));
    process.exit(1);
  }
  const код = создано.тело.код;
  const пропуск = создано.тело.пропуск;
  for (let i = 0; i < МЕСТ - 1; i++) await спросить('/ход', { код: код, пропуск: пропуск, действие: 'бот' });
  await спросить('/ход', { код: код, пропуск: пропуск, действие: 'начать' });

  let дуракПрошлой = null;      // номер места или null (первая партия / ничья)
  let проверокСделано = 0;

  for (let партия = 1; партия <= ПАРТИЙ; партия++) {
    await спать(150);
    let вид = await состояние(код, пропуск);
    const застолом = вид.застолом || [];
    const ходит = (застолом.filter(function (м) { return м.ходит; })[0] || {}).номер;
    const отбивается = (застолом.filter(function (м) { return м.отбивается; })[0] || {}).номер;

    if (дуракПрошлой !== null) {
      {
        проверокСделано++;
        const ждём = соседПеред(застолом, дуракПрошлой);
        проверить(отбивается === дуракПрошлой,
          'партия ' + партия + ': дурак прошлой — ' + имяМеста(застолом, дуракПрошлой) +
          ', отбиваться должен он, а отбивается ' + имяМеста(застолом, отбивается));
        проверить(ходит === ждём,
          'партия ' + партия + ': нападать должен ' + имяМеста(застолом, ждём) +
          ', а нападает ' + имяМеста(застолом, ходит));
      }
      console.log('  партия ' + партия + ': прошлый дурак — ' + имяМеста(застолом, дуракПрошлой) +
        '; нападает ' + имяМеста(застолом, ходит) + ', отбивается ' + имяМеста(застолом, отбивается));
    } else {
      console.log('  партия ' + партия + ': дурака прошлой партии нет (первая или ничья) — ' +
        'первый ход у младшего козыря; нападает ' + имяМеста(застолом, ходит));
    }

    // Доигрываем: за себя ходим сами, за ботов ходит сервер.
    let шагов = 0;
    while (шагов++ < ПРЕДЕЛ_ШАГОВ) {
      вид = await состояние(код, пропуск);
      if (вид.завершена || вид.этап === 'конец') break;
      if (вид.яХожу || вид.яОтбиваюсь) {
        const вышло = await походитьЗаСебя(код, пропуск, вид);
        if (!вышло) await спать(60);
      } else {
        await спать(40);
      }
    }
    вид = await состояние(код, пропуск);
    if (!вид.завершена && вид.этап !== 'конец') {
      console.log('  ПРОВАЛ: партия ' + партия + ' не доигралась за ' + ПРЕДЕЛ_ШАГОВ + ' шагов');
      провалов++;
      break;
    }
    const проигравшие = (вид.застолом || []).filter(function (м) { return м.проиграл; });
    дуракПрошлой = проигравшие.length > 0 ? проигравшие[0].номер : null;
    console.log('     кончилась: ' + (дуракПрошлой === null ? 'ничья'
      : 'дурак — ' + имяМеста(вид.застолом, дуракПрошлой)));

    await спросить('/ход', { код: код, пропуск: пропуск, действие: 'ещё' });
    await спать(250);
  }

  console.log('\nсверок правила сделано: ' + проверокСделано + ', провалов: ' + провалов);
  if (проверокСделано === 0) {
    console.log('ОСТОРОЖНО: правило ни разу не проверилось — все партии кончились ничьёй?');
  }
  console.log(провалов === 0
    ? '=== Итог: сервер сажает ходить на дурака, как и просили ==='
    : '=== Итог: СЕРВЕР ХОДИТ НЕ ПО ПРАВИЛУ — смотрите провалы выше ===');
  process.exit(провалов === 0 && проверокСделано > 0 ? 0 : 1);
})().catch(function (е) {
  console.log('Проверка сорвалась: ' + е.message);
  process.exit(1);
});
