'use strict';
/* =====================================================================
   ЖИВЫЕ ЛОББИ, Э1: чистые функции личин (server/личины.js).
   Без сервера и без таймеров. Проверяем:
     1) пулЛобби: ровно N разных номеров, по умолчанию 20, не больше 40;
     2) срокСтола: 4–12 минут, значения разные;
     3) реакция: только текст из закрытого списка, без бросков;
     4) частоты на 10 000 жребиев — в коридоре плана (60/50/55/15 %);
     5) паузы реакции — в границах плана;
     6) зеркало: смайлик на смайлик, «Привет!» на «Привет!»,
        бросок и неизвестное — молчание;
     7) сильные и слабые личины говорят по-разному;
     8) кулдаун 20 секунд хранится в переданном состоянии.
   Запуск:  node tests/личины-лобби-функции.js
   Ломающий запуск (порча модуля в ПАМЯТИ, файл проекта не трогаем):
     node tests/личины-лобби-функции.js --сломать=реакция   — «всегда отвечает»
     node tests/личины-лобби-функции.js --сломать=пул       — пул с повтором
     node tests/личины-лобби-функции.js --сломать=кулдаун   — без кулдауна
   Каждая порча обязана дать провалы и код 1.
   ===================================================================== */

const path = require('path');
const fs = require('fs');
const Module = require('module');

const КОРЕНЬ = path.join(__dirname, '..');
const ПУТЬ = path.join(КОРЕНЬ, 'server', 'личины.js');

const ПОРЧИ = {
  'реакция': ['if (жребий() >= правило.шанс) return null;', 'if (false) return null;'],
  'пул': ['return вперемешку.slice(0, нужно);', 'return вперемешку.slice(0, Math.max(0, нужно - 1)).concat(нужно > 0 ? [вперемешку[0]] : []);'],
  'кулдаун': ['if (Number.isFinite(состояние.последняя) && сейчас - состояние.последняя < КУЛДАУН_РЕАКЦИИ_МС) return null;', '']
};

const аргПорчи = process.argv.find(function (а) { return а.indexOf('--сломать=') === 0; });
const порча = аргПорчи ? аргПорчи.slice('--сломать='.length) : '';

function загрузитьМодуль() {
  if (!порча) return require(ПУТЬ);
  if (!ПОРЧИ[порча]) { console.log('неизвестная порча: ' + порча); process.exit(2); }
  let текст = fs.readFileSync(ПУТЬ, 'utf8');
  const было = ПОРЧИ[порча][0];
  // Не нашли, что портить — это провал самой проверки, а не «всё хорошо».
  if (текст.split(было).length !== 2) { console.log('порча не применилась: ' + порча); process.exit(2); }
  текст = текст.replace(было, function () { return ПОРЧИ[порча][1]; });
  const м = new Module(ПУТЬ, module);
  м.filename = ПУТЬ;
  м.paths = Module._nodeModulePaths(path.dirname(ПУТЬ));
  м._compile(текст, ПУТЬ);
  м.loaded = true;
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК (' + порча + ') — проверка обязана покраснеть ***');
  return м.exports;
}

const личины = загрузитьМодуль();

let проверок = 0;
const провалы = [];
function проверить(условие, что) {
  проверок++;
  if (!условие) { провалы.push(что); console.log('  ПРОВАЛ: ' + что); }
}

/* Повторяемый жребий (mulberry32): одни и те же числа от запуска к запуску. */
function жребийИзЗерна(зерно) {
  let а = зерно >>> 0;
  return function () {
    а = (а + 0x6D2B79F5) >>> 0;
    let т = Math.imul(а ^ (а >>> 15), 1 | а);
    т = (т + Math.imul(т ^ (т >>> 7), 61 | т)) ^ т;
    return ((т ^ (т >>> 14)) >>> 0) / 4294967296;
  };
}

const ЖЕРЕБИЙ = 10000;
const ПОВОДЫ_ПЛАНА = {
  'сел': { шанс: 0.60, отМс: 2000, доМс: 6000 },
  'победа': { шанс: 0.55, отМс: 1500, доМс: 5000 },
  'поражение': { шанс: 0.55, отМс: 1500, доМс: 5000 },
  'ожидание': { шанс: 0.15, отМс: 1000, доМс: 3000 }
};

function проверитьПул() {
  const умолчание = личины.пулЛобби();
  проверить(умолчание.length === 20, 'пул по умолчанию — ровно 20 (получили ' + умолчание.length + ')');
  for (const N of [1, 5, 12, 20, 40]) {
    const пул = личины.пулЛобби(N, жребийИзЗерна(N));
    проверить(пул.length === N, 'пул на ' + N + ' — ровно ' + N + ' личин (получили ' + пул.length + ')');
    const номера = new Set(пул.map(function (л) { return л.номер; }));
    проверить(номера.size === N, 'пул на ' + N + ': номера разные (разных ' + номера.size + ')');
    проверить(пул.every(function (л) { return личины.этоЛичина(л.номер); }), 'пул на ' + N + ': все — настоящие личины');
  }
  проверить(личины.пулЛобби(1000).length === личины.все().length, 'пул не больше всего списка личин');
  проверить(личины.пулЛобби(0).length === 0, 'пул на 0 — пустой');
  // Состав зависит от жребия: имена берутся из всего списка, а не «первые N».
  const первые = new Set();
  for (let з = 1; з <= 30; з++) личины.пулЛобби(20, жребийИзЗерна(з)).forEach(function (л) { первые.add(л.номер); });
  проверить(первые.size > 30, 'за 30 раздач пула встретилось больше 30 разных личин (было ' + первые.size + ')');
  // Много раздач подряд — повторов внутри пула не бывает ни разу.
  let сПовтором = 0;
  for (let з = 0; з < 500; з++) {
    const пул = личины.пулЛобби(20, жребийИзЗерна(1000 + з));
    if (new Set(пул.map(function (л) { return л.номер; })).size !== 20) сПовтором++;
  }
  проверить(сПовтором === 0, 'в 500 пулах повторов нет (с повтором: ' + сПовтором + ')');
}

function проверитьСрок() {
  const жребий = жребийИзЗерна(7);
  const сроки = [];
  for (let i = 0; i < 1000; i++) сроки.push(личины.срокСтола(жребий));
  const ПРЕДЕЛ_МИН = 4 * 60000, ПРЕДЕЛ_МАКС = 12 * 60000;
  проверить(Math.min.apply(null, сроки) >= ПРЕДЕЛ_МИН, 'срок стола не меньше 4 минут');
  проверить(Math.max.apply(null, сроки) <= ПРЕДЕЛ_МАКС, 'срок стола не больше 12 минут');
  проверить(new Set(сроки).size > 900, 'сроки разные у разных столов');
  проверить(Math.min.apply(null, сроки) < 5 * 60000 && Math.max.apply(null, сроки) > 11 * 60000, 'срок гуляет по всему коридору 4–12 минут');
  проверить(личины.срокСтола(function () { return 0; }) === ПРЕДЕЛ_МИН, 'жребий 0 — ровно 4 минуты');
  проверить(личины.срокСтола(function () { return 0.999999; }) <= ПРЕДЕЛ_МАКС, 'жребий почти 1 — не больше 12 минут');
}

/* Бросаем жребий ЖЕРЕБИЙ раз с чистым состоянием (кулдауна нет). */
function прогнатьПовод(повод, сила, зерно) {
  const жребий = жребийИзЗерна(зерно);
  const ответы = [];
  for (let i = 0; i < ЖЕРЕБИЙ; i++) {
    const р = личины.реакция(повод, { сила: сила, сейчас: 1000000 }, жребий);
    if (р) ответы.push(р);
  }
  return ответы;
}

function проверитьЧастотыИТексты() {
  const закрытый = new Set(личины.ТЕКСТЫ_РЕАКЦИЙ);
  проверить(закрытый.size >= 15, 'закрытый список текстов не пуст (' + закрытый.size + ')');

  let зерно = 100;
  for (const вид of Object.keys(ПОВОДЫ_ПЛАНА)) {
    const план = ПОВОДЫ_ПЛАНА[вид];
    const ответы = прогнатьПовод(вид, 'средний', зерно++);
    проверить(ответы.length > 0, '«' + вид + '»: хоть один ответ нашёлся (иначе проверка слепая)');
    const доля = ответы.length / ЖЕРЕБИЙ;
    проверить(Math.abs(доля - план.шанс) <= 0.03, '«' + вид + '»: доля ответов ' + доля.toFixed(3) + ' в коридоре ' + план.шанс + ' ± 0.03');
    проверить(ответы.every(function (р) { return закрытый.has(р.текст); }), '«' + вид + '»: все тексты — из закрытого списка');
    проверить(ответы.every(function (р) { return р.черезМс >= план.отМс && р.черезМс <= план.доМс; }),
      '«' + вид + '»: пауза в пределах ' + план.отМс + '–' + план.доМс + ' мс');
    проверить(new Set(ответы.map(function (р) { return р.текст; })).size >= 2, '«' + вид + '»: ответы разнообразны');
  }

  // Знак человека: тот же коридор 50 %, ответ зеркальный.
  const знаки = ['🙂', '👍', 'Привет!', 'Хороший ход!', 'Удачи!'];
  for (const текстЗнака of знаки) {
    const ответы = прогнатьПовод({ вид: 'знак', текст: текстЗнака }, 'средний', зерно++);
    const доля = ответы.length / ЖЕРЕБИЙ;
    проверить(ответы.length > 0, 'знак «' + текстЗнака + '»: ответ нашёлся');
    проверить(Math.abs(доля - 0.50) <= 0.03, 'знак «' + текстЗнака + '»: доля ответов ' + доля.toFixed(3) + ' в коридоре 0.5 ± 0.03');
    проверить(ответы.every(function (р) { return закрытый.has(р.текст) && р.черезМс >= 1500 && р.черезМс <= 4000; }),
      'знак «' + текстЗнака + '»: ответ из списка, пауза 1.5–4 с');
  }
  проверить(прогнатьПовод({ вид: 'знак', текст: '🙂' }, 'средний', 900).every(function (р) { return р.текст === '🙂'; }), 'на 🙂 отвечают только 🙂');
  проверить(прогнатьПовод({ вид: 'знак', текст: 'Привет!' }, 'средний', 901).every(function (р) { return р.текст === 'Привет!'; }), 'на «Привет!» отвечают только «Привет!»');

  // Броски и неизвестное — молчание; бросков в ответах нет никогда.
  for (const чужое of ['🍅', 'бросок', '📄 бумажка', '', undefined, null]) {
    проверить(прогнатьПовод({ вид: 'знак', текст: чужое }, 'средний', 902).length === 0, 'на непонятный знак (' + String(чужое) + ') молчит');
  }
  проверить(личины.реакция('несуществующий', { сила: 'средний' }, function () { return 0; }) === null, 'неизвестный повод — молчание');
  проверить(личины.реакция('сел', null, function () { return 0; }) === null, 'без состояния — молчание');
  const запрещённые = личины.ТЕКСТЫ_РЕАКЦИЙ.filter(function (т) { return /[🍅📄🥚💩🪨]|бросок|помидор|бумаж/iu.test(т); });
  проверить(запрещённые.length === 0, 'в закрытом списке нет бросков');
}

function проверитьСилу() {
  const текстыСильных = new Set(прогнатьПовод('сел', 'сильный', 300).map(function (р) { return р.текст; }));
  const текстыСлабых = new Set(прогнатьПовод('сел', 'слабый', 301).map(function (р) { return р.текст; }));
  проверить(текстыСильных.size > 0 && текстыСлабых.size > 0, 'у сильных и слабых есть ответы на «сел»');
  проверить(текстыСильных.has('😎') && !текстыСлабых.has('😎'), 'любимое сильных (😎) слабые не говорят');
  проверить(текстыСлабых.has('😄') && !текстыСильных.has('😄'), 'любимое слабых (😄) сильные не говорят');
  const слабыеПроиграли = new Set(прогнатьПовод('поражение', 'слабый', 302).map(function (р) { return р.текст; }));
  const сильныеПроиграли = new Set(прогнатьПовод('поражение', 'сильный', 303).map(function (р) { return р.текст; }));
  проверить(слабыеПроиграли.has('😅') && !сильныеПроиграли.has('😅'), 'после проигрыша 😅 — у слабых, не у сильных');
}

function проверитьКулдаун() {
  const всегда = function () { return 0; };   // жребий 0 — шанс всегда выпадает
  const л = { сила: 'средний', сейчас: 5000 };
  const первая = личины.реакция('сел', л, всегда);
  проверить(первая !== null, 'первая реакция состоялась');
  проверить(л.последняя === 5000, 'время реакции записано в переданное состояние (' + л.последняя + ')');
  л.сейчас = 5000 + личины.КУЛДАУН_РЕАКЦИИ_МС - 1;
  проверить(личины.реакция('сел', л, всегда) === null, 'через 19,999 с — ещё молчит');
  проверить(личины.реакция({ вид: 'знак', текст: '🙂' }, л, всегда) === null, 'и на знак в кулдаун молчит');
  проверить(личины.реакция('победа', л, всегда) === null, 'и после партии в кулдаун молчит');
  л.сейчас = 5000 + личины.КУЛДАУН_РЕАКЦИИ_МС;
  проверить(личины.реакция('сел', л, всегда) !== null, 'ровно через 20 с — снова отвечает');
  проверить(личины.КУЛДАУН_РЕАКЦИИ_МС === 20000, 'кулдаун — 20 секунд');

  // Серия: 100 знаков подряд за 60 с, жребий «всегда отвечать» — не больше 3 ответов.
  const серия = { сила: 'средний' };
  let ответов = 0;
  for (let i = 0; i < 100; i++) {
    серия.сейчас = i * 600;
    if (личины.реакция({ вид: 'знак', текст: '👍' }, серия, всегда)) ответов++;
  }
  проверить(ответов >= 1 && ответов <= 3, '100 знаков за 60 с — ответов не больше 3 (получили ' + ответов + ')');

  // Кулдаун у каждой личины свой.
  const другая = { сила: 'слабый', сейчас: 5000 };
  проверить(личины.реакция('сел', другая, всегда) !== null, 'у другой личины кулдаун свой');
}

