/* =====================================================================
   ОТКРЫТЫЕ СТОЛЫ: «нашёл игру в списке и сел, без кода и ссылки».

   Что проверяем. Две новые двери сервера:
     POST /открытые-столы — список столов, которые хозяева объявили
       открытыми: игра, числа мест, имена сидящих и ключ стола;
     POST /сесть — посадка за выбранный стол по этому ключу.

   Чем эти двери опасны. Первая показывает посторонним живые столы, и её
   легко превратить в карту сервера: кто сейчас играет и какие у комнат
   коды. Вторая сажает человека за чужой стол. Поэтому проверяется не
   только «работает», а прежде всего:

     — кода стола в списке нет вовсе (код — вещь долгая: уехав один раз,
       он остаётся годным и после того, как хозяин стол закрыл);
     — номеров Telegram в ответе нет;
     — закрытый стол (созданный для друга по коду) в списке не виден;
     — чужим ключом за стол не сесть, использованным — тоже;
     — двое, нажавшие «Сесть» разом, не занимают одно место вдвоём.

   Настоящего Telegram здесь нет: сервер отдаёт наружу одну щель для
   проверок (оснасткаДляПроверки) — выдуманный токен и поддельная труба.
   Данные уведены в сторону переменной ДАННЫЕ_ИГРЫ, боевые знакомства
   на диске не трогаются. Боевой сервер 8790 не трогается тоже: проверка
   поднимает свою копию на своём порту.

   Запуск:
       node tests/открытые-столы-сервер.js
       node tests/открытые-столы-сервер.js 8797      (свой порт)

   Ломающий прогон (проверка обязана покраснеть):
       node tests/открытые-столы-сервер.js --сломать
   «--сломать» портит наблюдаемое в памяти самой проверки, сервер не
   трогая: список столов подменяется одним выдуманным, за которым сидят
   сразу все, а любой ответ двери «Сесть» — пустой удачей. Тогда обязаны
   провалиться все четыре вида сверок: «стол виден и вот такой», «стола
   в списке нет», «дверь отказала» и «сел за стол». Ноль провалов при
   «--сломать» значит, что проверка спит.

   Выход 0 — провалов нет, 1 — есть.
   ===================================================================== */

