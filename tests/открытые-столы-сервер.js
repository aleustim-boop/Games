  проверить(мусор.тело.принято === false,
    'непонятное «открыть» дверь не принимает: только настоящее да или нет');

  console.log('5. Чужим столом распоряжается только хозяин');
  const столЖени = await создатьСтол(ЖЕНЯ, 'Женя', { мест: 3 });
  const вошлаЗина = await спросить('/войти', {
    код: столЖени.код, имя: 'Зина', initData: подписьИгрока(ЗИНА, 'Зина')
  });
  проверить(вошлаЗина.код === 200 && Boolean(вошлаЗина.тело.пропуск),
    'гость по коду садится за стол-компанию, как и раньше');
  const чужой = await спросить('/ход', {
    код: столЖени.код, пропуск: вошлаЗина.тело.пропуск,
    действие: 'открыть-стол', открыть: true
  });
  проверить(чужой.тело.принято === false, 'не хозяин чужой стол для всех не открывает');
  проверить(typeof чужой.тело.причина === 'string' && чужой.тело.причина.length > 10,
    'отказ не хозяину объясняется словами');
  const уКати = await список(КАТЯ, 'Катя');
  проверить(столГде(уКати, 'Женя') === null, 'после отказа стол так и не появился в списке');

  console.log('6. Полный стол в списке не показываем');
  await действие(столЖени, { действие: 'открыть-стол', открыть: true });
