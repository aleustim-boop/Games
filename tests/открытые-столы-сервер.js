  проверить(вошёлИгорь.код === 200, 'третий гость сел за стол на троих');
  const уМиши = await список(МИША, 'Миша');
  проверить(столГде(уМиши, 'Женя') === null,
    'полный стол из списка уходит: садиться туда уже некуда');

  console.log('7. Посадка по ключу: выбрал стол — и за столом');
  const уНины = await список(НИНА, 'Нина');
