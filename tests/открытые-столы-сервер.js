  проверить(Array.isArray(безПодписи.тело.столы) && безПодписи.тело.столы.length === 0,
    'без подписи Telegram столов не показываем вовсе');
  проверить(typeof безПодписи.тело.причина === 'string' && безПодписи.тело.причина.length > 10,
    'отказ без подписи объясняется словами, понятными человеку');

  console.log('2. Открытый стол виден, и в ответе нет ни кода, ни номеров');
  const столАни = await создатьСтол(АНЯ, 'Аня', { открытый: true });
  const уБори = await список(БОРЯ, 'Боря');
  const виден = столГде(уБори, 'Аня');
  проверить(уБори.тело.ок === true && уБори.тело.узналиВас === true,
    'игрока с подписью Telegram список узнаёт');
  проверить(виден !== null, 'открытый стол Ани виден в общем списке');
  if (виден) {
    проверить(виден.игра === 'дурак', 'у строки стола сказано, во что играют');
    проверить(виден.мест === 2 && виден.занято === 1 && виден.свободно === 1,
      'числа мест честные: занято одно из двух, одно свободно');
    проверить(виден.игроки.length === 1 && виден.игроки[0] === 'Аня',
      'в строке названы имена сидящих людей');
    проверить(виден.ботов === 0, 'ботов за этим столом нет, так и сказано');
    проверить(typeof виден.ключ === 'string' && виден.ключ.length >= 32,
      'у стола есть ключ, которым за него садятся');
    проверить(виден.код === undefined, 'кода стола в строке списка нет вовсе');
  }
  const словаСписка = ответБезКлючей(уБори);
  проверить(словаСписка.indexOf(столАни.код) === -1,
    'кода стола нет нигде в ответе списка — даже строкой');
  let номерВОтвете = '';
  for (const номер of ВСЕ_НОМЕРА) {
    if (словаСписка.indexOf(String(номер)) !== -1) номерВОтвете = String(номер);
  }
  проверить(номерВОтвете === '',
    'номеров Telegram в ответе списка нет (нашёлся ' + номерВОтвете + ')');

  console.log('3. Закрытый стол для друга в списке не виден');
  const столВити = await создатьСтол(ВИТЯ, 'Витя');
  const уГали = await список(ГАЛЯ, 'Галя');
  проверить(столГде(уГали, 'Витя') === null,
    'обычный стол «для друга по коду» посторонним не показывается');

  console.log('4. Переключатель хозяина «Пустить любого»');
  const открыл = await действие(столВити, { действие: 'открыть-стол', открыть: true });
  проверить(открыл.тело.принято === true, 'хозяин может открыть свой стол для всех');
  проверить(Boolean(открыл.тело.состояние) && открыл.тело.состояние.открытыйСтол === true,
    'после открытия состояние стола (дурак) само отдаёт открытыйСтол: true');
  const уДимы = await список(ДИМА, 'Дима');
  проверить(столГде(уДимы, 'Витя') !== null, 'открытый стол Вити появился в списке');
  const закрыл = await действие(столВити, { действие: 'открыть-стол', открыть: false });
  проверить(закрыл.тело.принято === true, 'хозяин может закрыть стол обратно');
  проверить(Boolean(закрыл.тело.состояние) && закрыл.тело.состояние.открытыйСтол === false,
    'после закрытия состояние стола (дурак) отдаёт открытыйСтол: false');
  const уЕгора = await список(ЕГОР, 'Егор');
  проверить(столГде(уЕгора, 'Витя') === null, 'закрытый обратно стол из списка пропал');
