'use strict';

/* =====================================================================
   Проверка этапа Э3 «сыграть с другом»: «Поделиться приложением».

   1. bot/бот.js — кнопка, которая шлёт общую ссылку на весь сборник
      (без конкретной игры и стола), подписана «Поделиться приложением»,
      а не старым «Позвать друга»; тексты ТЕКСТ_ПРИГЛАШЕНИЯ и приветствие()
      называют КАЖДУЮ игру сборника — список берётся из одной таблицы
      server/названия.js, а не пишется в тексте руками.
   2. js/похвастаться.js — метка нард и деберца в ссылке для похвастаться,
      и клиентские «слова о победе» (запасной путь без сервера) — теми же
      формами «в чём», что и сервер (поле «вИгре» из server/названия.js),
      для всех сетевых игр, а не только дурака и шашек.

   Подписи кнопок в лобби игр (index.html, шашки.html, нарды.html…) —
   отдельный этап Э3б, здесь не проверяются: там ещё осталось старое
   «Пригласить друзей», и это ожидаемо до Э3б.

   Ломающий запуск — в самом низу файла: копия бот.js со старым текстом
   и копия похвастаться.js со старым «вИгре» (bugfix отменён) — обе
   должны покраснеть на этой же проверке.

   Запуск: node tests/поделиться-приложением.js
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const vm = require('vm');

const КОРЕНЬ = path.resolve(__dirname, '..');
const ПУТЬ_БОТА = path.join(КОРЕНЬ, 'bot', 'бот.js');
const ПУТЬ_ПОХВАСТАТЬСЯ = path.join(КОРЕНЬ, 'js', 'похвастаться.js');
// Список игр и слово «вИгре» — источник истины один на весь проект,
// а не переписанная тут копия (иначе проверка и код могут разойтись
// и обе соврать одинаково).
const названия = require(path.join(КОРЕНЬ, 'server', 'названия.js'));

let всёХорошо = true;
function проверить(что, правда) {
  console.log((правда ? '  ок   ' : '  БЕДА ') + что);
  if (!правда) всёХорошо = false;
}

/* ---------------------------------------------------------------------
   1. Тексты bot/бот.js — читаем исходник как текст (сам бот не запускаем:
   ему для старта нужен настоящий bot/.env с токеном, а этот файл его
   не читает никогда). Тексты ТЕКСТ_ПРИГЛАШЕНИЯ и приветствие() выполняем
   в песочнице vm: между маркерами НАЧАЛО-ТЕКСТЫ-ИГР/КОНЕЦ-ТЕКСТЫ-ИГР
   лежит чистый код без сети и файлов, ему нужна только таблица
   server/названия.js.
   --------------------------------------------------------------------- */

/** Собрать список бед в текстах бота. Пустой список — всё в порядке.
    Работает и на настоящем файле, и на испорченной копии для ломающего
    запуска — поэтому не падает и не завершает процесс сама. */
function бедыТекстовБота(исходник) {
  const беды = [];

  if (исходник.indexOf('Позвать друга') !== -1) {
    беды.push('в файле осталась старая подпись «Позвать друга»');
  }
  if (исходник.indexOf('Поделиться приложением') === -1) {
    беды.push('подписи «Поделиться приложением» не нашлось ни разу');
  }

  const меткаНачала = исходник.indexOf('НАЧАЛО-ТЕКСТЫ-ИГР');
  const меткаКонца = исходник.indexOf('КОНЕЦ-ТЕКСТЫ-ИГР');
  if (меткаНачала === -1 || меткаКонца === -1) {
    беды.push('маркеры НАЧАЛО-ТЕКСТЫ-ИГР/КОНЕЦ-ТЕКСТЫ-ИГР не найдены — тексты не проверены вовсе');
    return беды;
  }
  // Сами слова-маркеры лежат внутри комментариев-«скобок» /* ... */ — код
  // нужен строго между закрытием открывающего и открытием закрывающего,
  // иначе в песочницу попадёт хвост комментария как будто это JS.
  const начало = исходник.indexOf('*/', меткаНачала) + 2;
  const конец = исходник.lastIndexOf('/*', меткаКонца);
  if (начало < 2 || конец === -1 || конец <= начало) {
    беды.push('код между маркерами не нашёлся (комментарии-скобки /* */ вокруг маркеров пропали)');
    return беды;
  }

  const песочница = { Названия: названия, module: { exports: {} } };
  vm.createContext(песочница);
  try {
    vm.runInContext(
      исходник.slice(начало, конец) +
      '\nmodule.exports = { ТЕКСТ_ПРИГЛАШЕНИЯ: ТЕКСТ_ПРИГЛАШЕНИЯ, приветствие: приветствие };',
      песочница, { filename: 'бот-тексты-игр.js' });
  } catch (сбой) {
    беды.push('тексты бота не выполнились: ' + сбой.message);
    return беды;
  }

  const { ТЕКСТ_ПРИГЛАШЕНИЯ, приветствие } = песочница.module.exports;
  const текстПриветствия = typeof приветствие === 'function' ? приветствие('Аня') : '';
  for (const строка of названия.ИГРЫ) {
    if (!ТЕКСТ_ПРИГЛАШЕНИЯ || ТЕКСТ_ПРИГЛАШЕНИЯ.indexOf(строка.название) === -1) {
      беды.push('ТЕКСТ_ПРИГЛАШЕНИЯ не называет игру «' + строка.название + '»');
    }
    if (!текстПриветствия || текстПриветствия.indexOf(строка.название) === -1) {
      беды.push('приветствие не называет игру «' + строка.название + '»');
    }
  }
  return беды;
}

console.log('=== 1. bot/бот.js: подпись «Поделиться приложением» и тексты про все игры ===');
const исходникБота = fs.readFileSync(ПУТЬ_БОТА, 'utf8');
const бедыБота = бедыТекстовБота(исходникБота);
проверить('bot/бот.js: бед не найдено (' + бедыБота.length + ')', бедыБота.length === 0);
бедыБота.forEach(function (б) { console.log('      - ' + б); });

/* ---------------------------------------------------------------------
   2. js/похвастаться.js — метка нард и деберца в ссылке, и слова победы
   (запасной путь без сервера) для всех сетевых игр теми же формами,
   что сервер (названия.вИгре). Файл — браузерный, поэтому запускаем его
   в песочнице vm с поддельными window/document/fetch — тот же приём,
   что и в tests/проверка-похвастаться-сервер-и-сеть.js.
   --------------------------------------------------------------------- */

/** Окно с компьютера без Telegram-«поверх»: похвастаться() уходит сразу
    в буфер обмена — оттуда и читаем получившиеся слова. */
function собратьОкноБуфера() {
  const буфер = { текст: null };
  const память = new Map();
  const памятьБраузера = {
    getItem: function (к) { return память.has(к) ? память.get(к) : null; },
    setItem: function (к, ч) { память.set(к, String(ч)); },
    removeItem: function (к) { память.delete(к); }
  };
  const окно = {
    location: { search: '', protocol: 'https:', href: 'https://пример/Games/',
                origin: 'https://пример', pathname: '/Games/', host: 'пример' },
    localStorage: памятьБраузера, sessionStorage: памятьБраузера,
    navigator: { clipboard: { writeText: function (т) { буфер.текст = т; return Promise.resolve(); } } },
    // platform «tdesktop»: не телефон (список чатов не открываем) и без
    // shareMessage (выбор чата поверх недоступен) — значит сразу буфер.
    Telegram: { WebApp: { initData: '', platform: 'tdesktop' } }
  };
  const страница = { getElementById: function () { return null; }, addEventListener: function () {},
                     querySelectorAll: function () { return []; }, readyState: 'complete' };
  const окружение = {
    window: окно, document: страница,
    console: { warn: function () {}, log: function () {}, error: function () {} },
    fetch: function () {
      return Promise.resolve({ ok: false, status: 0, json: function () { return Promise.resolve({}); } });
    },
    setTimeout: setTimeout, clearTimeout: clearTimeout,
    URLSearchParams: URLSearchParams, URL: URL, AbortController: AbortController,
    Promise: Promise, JSON: JSON, Date: Date, Math: Math
  };
  окружение.globalThis = окружение;
  return { окно: окно, окружение: окружение, буфер: буфер };
}

/** Собрать беды в словах победы js/похвастаться.js на заданном исходнике.
    Пустой список — всё в порядке. Проверяет все сетевые игры из
    названия.сетевыеИгры() без поля «слова» в описании — то есть именно
    запасные, самостоятельно собранные клиентом слова. */
async function бедыСловПобеды(исходникПохвастаться) {
  const беды = [];

  if (!/'нарды':\s*'nardy'/.test(исходникПохвастаться)) {
    беды.push('МЕТКИ_ИГР не знает нарды (nardy)');
  }
  if (!/'деберц':\s*'deberts'/.test(исходникПохвастаться)) {
    беды.push('МЕТКИ_ИГР не знает деберц (deberts)');
  }

  for (const игра of названия.сетевыеИгры()) {
    const { окно, окружение, буфер } = собратьОкноБуфера();
    try {
      vm.runInNewContext(исходникПохвастаться, окружение, { filename: 'похвастаться.js' });
    } catch (сбой) {
      беды.push(игра + ': файл не выполнился в песочнице: ' + сбой.message);
      continue;
    }
    if (!окно.Сеть || typeof окно.Сеть.похвастаться !== 'function') {
      беды.push(игра + ': window.Сеть.похвастаться не появилась');
      continue;
    }
    // Без поля «слова» — именно тот случай, когда клиент обязан собрать
    // слова сам (у нард и деберца своей «словаПобедыДляЧата» ещё нет).
    await окно.Сеть.похвастаться({ игра: игра, исход: 'победа', соперники: 'боты', уровень: 'сложный', игроков: 2 });
    const слова = буфер.текст ? буфер.текст.split(' https://')[0] : '';
    const ожидаемоеВИгре = названия.словаИгры(игра).вИгре;

    if (!слова) {
      беды.push(игра + ': слова не собрались вовсе (буфер пуст)');
      continue;
    }
    if (слова.indexOf(ожидаемоеВИгре) === -1) {
      беды.push(игра + ': слова не содержат «' + ожидаемоеВИгре + '» (получили: «' + слова + '»)');
    }
    if (игра !== 'дурак' && /дурак/i.test(слова)) {
      беды.push(игра + ': слова называют игру дураком (получили: «' + слова + '»)');
    }
  }
  return беды;
}

console.log('\n=== 2. js/похвастаться.js: метки нард/деберца и слова победы всех сетевых игр ===');
const исходникПохвастаться = fs.readFileSync(ПУТЬ_ПОХВАСТАТЬСЯ, 'utf8');

(async function () {
  const бедыПохвастаться = await бедыСловПобеды(исходникПохвастаться);
  проверить('js/похвастаться.js: бед не найдено (' + бедыПохвастаться.length + ')', бедыПохвастаться.length === 0);
  бедыПохвастаться.forEach(function (б) { console.log('      - ' + б); });

  /* -------------------------------------------------------------------
     3. Ломающие запуски — обе проверки обязаны покраснеть на порченых
     копиях. Копии — во временной папке, настоящие файлы не трогаем.
     ------------------------------------------------------------------- */
  console.log('\n=== 3. Ломающие запуски (копии во временной папке, не настоящие файлы) ===');
  const стенд = fs.mkdtempSync(path.join(os.tmpdir(), 'поделиться-приложением-'));

  // 3a. Бот со старым текстом и старой подписью кнопки.
  const старыеТекстыИгр =
    "function перечислитьЗапятыми(слова) { return слова.join(', '); }\n" +
    'const ИМЕНА_ИГР = [];\n' +
    'const ТЕКСТ_ПРИГЛАШЕНИЯ =\n' +
    "  'Играем? Тут сборник настольных игр прямо в Telegram: дурак, шашки и шахматы.\\n' +\n" +
    "  'Ставить ничего не надо — открывай и выбирай.\\n' +\n" +
    "  'Можно с ботом, а можно вдвоём — живьём друг против друга.';\n" +
    'function строкаИгрыДляПриветствия(с) { return String(с); }\n' +
    'function приветствие(имя) {\n' +
    "  return 'Привет' + (имя ? ', ' + имя : '') + '! \\n\\n' +\n" +
    "    'Уже три настольные игры прямо в Telegram, ставить ничего не надо:\\n' +\n" +
    "    '• Дурак — с ботом или вдвоём с живым другом\\n' +\n" +
    "    '• Шашки — с ботом\\n' +\n" +
    "    '• Шахматы — с ботом\\n\\n' +\n" +
    "    'Жмите «Играть» и выбирайте, во что.\\n' +\n" +
    "    'А в общем чате напишите /играть — соберу стол прямо там.';\n" +
    '}\n';
  // Тот же приём, что и в бедыТекстовБота: код заменяем строго между
  // закрытием открывающего маркера-комментария и открытием закрывающего,
  // сами маркеры оставляем на месте, чтобы проверка их нашла.
  const н1 = исходникБота.indexOf('*/', исходникБота.indexOf('НАЧАЛО-ТЕКСТЫ-ИГР')) + 2;
  const к1 = исходникБота.lastIndexOf('/*', исходникБота.indexOf('КОНЕЦ-ТЕКСТЫ-ИГР'));
  const сломанныйБот = (исходникБота.slice(0, н1) + '\n' + старыеТекстыИгр + '\n' + исходникБота.slice(к1))
    .replace(/Поделиться приложением/g, 'Позвать друга');
  const путьСломанногоБота = path.join(стенд, 'бот-сломан.js');
  fs.writeFileSync(путьСломанногоБота, сломанныйБот, 'utf8');
  const бедыСломанногоБота = бедыТекстовБота(fs.readFileSync(путьСломанногоБота, 'utf8'));
  проверить('ломающий бот.js: проверка покраснела (найдено бед: ' + бедыСломанногоБота.length + ')',
    бедыСломанногоБота.length > 0);

  // 3b. похвастаться.js с отменённым исправлением: все игры снова получают
  //     слово «дурака» — воспроизводит баг из отчёта штаба буква в букву.
  const сломанныйПохвастаться = исходникПохвастаться.replace(/ВИГРЕ_ИГР\[что\.игра\]/g, "'в подкидном дураке'");
  проверить('ломающая подмена нашла, что менять (файл был другим)',
    сломанныйПохвастаться !== исходникПохвастаться);
  const путьСломанногоПохвастаться = path.join(стенд, 'похвастаться-сломан.js');
  fs.writeFileSync(путьСломанногоПохвастаться, сломанныйПохвастаться, 'utf8');
  const бедыСломанныхСлов = await бедыСловПобеды(fs.readFileSync(путьСломанногоПохвастаться, 'utf8'));
  проверить('ломающий похвастаться.js: проверка покраснела (найдено бед: ' + бедыСломанныхСлов.length + ')',
    бедыСломанныхСлов.length > 0);

  // Уборка за собой.
  try {
    for (const имя of fs.readdirSync(стенд)) fs.unlinkSync(path.join(стенд, имя));
    fs.rmdirSync(стенд);
  } catch (сбой) { /* временная папка не критична */ }

  console.log('\n' + (всёХорошо ? 'ИТОГ: всё сошлось.' : 'ИТОГ: есть беды.'));
  process.exit(всёХорошо ? 0 : 1);
})();
