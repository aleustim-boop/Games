/* =====================================================================
   ДУРАК, ЭКРАН КОМНАТЫ: подпись «Открыть подбор игроков» и пометка
   «в списке виден, подбор — только на двоих» не должны накладываться.

   Что делает: поднимает свой страничный сервер на свободном порту (боевой
   8790 не трогает), открывает index.html на 390x844 и 360x740, показывает
   экран комнаты, ставит в узлы те же слова, что берёт из общее/js/дурак-комната.js
   (подпись и пометка читаются из самого файла — второй копии текста нет),
   и сравнивает прямоугольники узлов: оба видимы, не пересекаются.

   Запуск:            node tests/дурак-подбор-подпись.js
   Ломающий запуск:   node tests/дурак-подбор-подпись.js --сломать <папка>
     Папка — копия, куда лишь кладётся испорченный style.css (пометка
     уезжает вверх на подпись). Файл проекта не портится.
   Перед запуском: node штаб/браузер-занят.js
   ===================================================================== */

const http = require('http');
const fs = require('fs');
const path = require('path');
const { chromium, подготовитьПодделку } = require('./браузер-робот.js');

const КОРЕНЬ = path.join(__dirname, '..');
const ПАПКА_СНИМКОВ = path.join(__dirname, 'снимки');
const РАЗМЕРЫ = [
  { ширина: 390, высота: 844 },
  { ширина: 360, высота: 740 }
];

const ТИПЫ = {
  '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8', '.png': 'image/png',
  '.jpg': 'image/jpeg', '.svg': 'image/svg+xml', '.woff2': 'font/woff2'
};

let всего = 0;
let провалов = 0;
function проверка(ок, что) {
  всего++;
  if (!ок) провалов++;
  console.log((ок ? 'ok   ' : 'ПРОВАЛ ') + что);
}

/* Слова берём из общее/js/дурак-комната.js: ищем строку по ключу. Не нашли — провал. */
function слово(ключ) {
  const текст = fs.readFileSync(path.join(КОРЕНЬ, 'общее', 'js', 'дурак-комната.js'), 'utf8');
  const совпало = new RegExp('\\n\\s*' + ключ + ":\\s*'([^']+)'").exec(текст);
  return совпало ? совпало[1] : null;
}

function поднятьСтраницы(папкаСтиля) {
  return new Promise((готово, ошибка) => {
    const сервер = http.createServer((запрос, ответ) => {
      let путь = запрос.url.split('?')[0];
      if (путь === '/') путь = '/index.html';
      try { путь = decodeURIComponent(путь); } catch (е) { /* как есть */ }
      /* style.css при ломающем запуске берётся из копии, остальное — из проекта */
      const основа = (папкаСтиля && путь === '/общее/css/style.css') ? папкаСтиля : КОРЕНЬ;
      fs.readFile(path.join(основа, путь), (е, данные) => {
        if (е) { ответ.writeHead(404); ответ.end('404'); return; }
        ответ.writeHead(200, { 'Content-Type': ТИПЫ[path.extname(путь)] || 'text/plain' });
        ответ.end(данные);
      });
    });
    сервер.on('error', ошибка);
    сервер.listen(0, '127.0.0.1', () => готово(сервер));
  });
}

/* Показывает комнату и кладёт слова; возвращает прямоугольники или null. */
function показатьИИзмерить(слова) {
  const у = document.getElementById('комната');
  if (!у) return { нет: 'комната' };
  for (let п = у; п && п !== document.documentElement; п = п.parentElement) {
    п.classList.remove('скрыт');
    п.hidden = false;
    if (п.classList.contains('экран')) п.classList.add('экран--виден');
  }
  const кнопка = document.getElementById('комната-подбор');
  const подпись = document.getElementById('комната-подбор-подпись');
  const пометка = кнопка && кнопка.querySelector('.комната__скоро');
  if (!кнопка || !подпись || !пометка) return { нет: 'подбор/подпись/пометка' };
  подпись.textContent = слова.подпись;
  пометка.textContent = слова.пометка;
  пометка.classList.remove('скрыт');
  кнопка.classList.remove('скрыт');
  const р = (у) => { const к = у.getBoundingClientRect(); return { л: к.left, п: к.right, в: к.top, н: к.bottom }; };
  return { подпись: р(подпись), пометка: р(пометка), кнопка: р(кнопка), ширинаОкна: window.innerWidth };
}

async function запустить() {
  const iСломать = process.argv.indexOf('--сломать');
  const папкаКопии = iСломать !== -1 ? process.argv[iСломать + 1] : null;
  if (iСломать !== -1 && !папкаКопии) { console.error('Нужна папка: --сломать <папка>'); process.exit(2); }
  const слова = { подпись: слово('подбор'), пометка: слово('подборТолькоНаДвоих') };
  проверка(Boolean(слова.подпись), 'подпись найдена в общее/js/дурак-комната.js: ' + слова.подпись);
  проверка(Boolean(слова.пометка), 'пометка найдена в общее/js/дурак-комната.js: ' + слова.пометка);
  if (!слова.подпись || !слова.пометка) return;

  if (!fs.existsSync(ПАПКА_СНИМКОВ)) fs.mkdirSync(ПАПКА_СНИМКОВ, { recursive: true });
  const сервер = await поднятьСтраницы(папкаКопии);
  const адрес = 'http://127.0.0.1:' + сервер.address().port;
  console.log('Страницы на ' + адрес + (папкаКопии ? ' (style.css из ' + папкаКопии + ')' : ''));
  const браузер = await chromium.launch();
  try {
    for (const р of РАЗМЕРЫ) {
      const имя = р.ширина + 'x' + р.высота;
      const контекст = await браузер.newContext({ viewport: { width: р.ширина, height: р.высота }, hasTouch: true });
      const страница = await контекст.newPage();
      await подготовитьПодделку(страница, { версия: '7.10' });
      await страница.goto(адрес + '/index.html', { waitUntil: 'domcontentloaded' });
      await страница.waitForTimeout(800);
      const м = await страница.evaluate(показатьИИзмерить, слова);
      проверка(!м.нет, имя + ': узлы найдены' + (м.нет ? ' (нет: ' + м.нет + ')' : ''));
      if (!м.нет) {
        const видим = (к) => (к.п - к.л) > 1 && (к.н - к.в) > 1;
        проверка(видим(м.подпись) && видим(м.пометка), имя + ': подпись и пометка видимы');
        const пересеклись = м.подпись.л < м.пометка.п && м.пометка.л < м.подпись.п &&
          м.подпись.в < м.пометка.н && м.пометка.в < м.подпись.н;
        проверка(!пересеклись, имя + ': подпись и пометка не пересекаются');
        проверка(м.пометка.п <= м.ширинаОкна + 0.5 && м.пометка.л >= -0.5, имя + ': пометка внутри экрана целиком');
        if (р.ширина === 390 && !папкаКопии) {
          await страница.screenshot({ path: path.join(ПАПКА_СНИМКОВ, 'дурак-подбор-подпись-390.png') });
        }
      }
      await контекст.close();
    }
  } finally {
    await браузер.close();
    сервер.close();
  }
}

запустить().then(() => {
  console.log('Итого проверок: ' + всего + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
}).catch((е) => {
  console.error('Стенд упал: ' + е.message);
  process.exit(2);
});
