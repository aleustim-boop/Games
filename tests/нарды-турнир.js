'use strict';

/* =====================================================================
   ТУРНИР НАРД. Сильнее ли новый уровень бота — числом, которому можно
   верить.

   ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, ЕСЛИ У БОТА ЕСТЬ САМОПРОВЕРКА. Самопроверка
   бота отвечает на вопрос «не сломан ли он»: играет двести партий и
   смотрит, что сильный обыгрывает слабого. Двухсот партий хватает
   только на большую разницу — случайная ошибка выборки там около семи
   процентов. Здесь вопрос другой и куда более тонкий: не «сильнее ли
   мастер случайного игрока», а «сильнее ли он ровно того соперника,
   который уже стоит в игре». Разница в этом матче ожидается в десять
   процентов, и мерить её надо иначе.

   ---------------------------------------------------------------------
   ЧЕМ ЭТОТ ТУРНИР ЧЕСТНЕЕ ПРОСТОГО ПРОГОНА

   1) ДУПЛИРОВАННЫЕ КУБИКИ. Каждая пара партий играется ОДНОЙ И ТОЙ ЖЕ
      последовательностью бросков, но стороны меняются. Повезло с кубиками
      в первой партии — ровно так же повезёт сопернику во второй, и
      везение вычитается само. Без этого приёма кубики шумят так, что
      разницу в десять процентов на пятистах партиях можно и не разглядеть.
      Так же меряют силу ботов в настоящих нардах.

   2) ЗЕРНО. Кубики берутся не из Math.random, а из общего генератора
      проекта с названным зерном: то же зерно — тот же турнир, до
      последнего броска. Спор «а у меня вышло другое» решается запуском.
      Тай-брейки самих ботов (из нескольких равных ходов берётся
      случайный) тоже посажены на повторимый поток.

   3) ПОГРЕШНОСТЬ ПЕЧАТАЕТСЯ РЯДОМ С ЧИСЛОМ. Доля побед без погрешности —
      это не измерение, а гадание: в прошлый раз в нардах пять прогонов
      по двести партий дали для одной и той же пары 45, 50, 54, 56 и 61
      процент. Печатаем размах, в который попадает истина с вероятностью
      95 из 100. Считается он по формуле для независимых партий, а пары у
      нас связаны нарочно — значит, настоящая погрешность ещё меньше
      напечатанной. Ошибаемся в сторону осторожности.

   ---------------------------------------------------------------------
   ГРАНИЦЫ ОБЪЯВЛЕНЫ ДО ПРОГОНА, а не подогнаны под результат.

     цель               мастер берёт у «сложного» не меньше 60%
     нижняя допустимая  57% — на пятистах партиях это уже не везение
     ниже 57%           не сдаём, ищем дальше в оценке
     лестница           «сложный» по-прежнему обыгрывает «лёгкого»
     время              ни один ход мастера не думается дольше 100 мс
                        (Node на машине разработчика примерно втрое
                        быстрее телефона, где обещано 300 мс)

   ---------------------------------------------------------------------
   ЗАПУСК

     node tests/нарды-турнир.js              500 партий в каждом матче
     node tests/нарды-турнир.js 100          быстрая проба
     node tests/нарды-турнир.js 500 777      другое зерно: проверить, не
                                             выпало ли число на удачных кубиках
     node tests/нарды-турнир.js 100 --сломать
         ЛОМАЮЩИЙ ЗАПУСК. Вместо мастера за него играет тот же «сложный».
         Соперники становятся одинаковыми, и проверка ОБЯЗАНА покраснеть.
         Если она при этом зелёная — верить ей нельзя и в обычный день.

   КОД ВОЗВРАТА. 0 — всё в порядке (а при ломающем запуске 0 значит
   «покраснела, как и должна»). 1 — провал.
   ===================================================================== */

const путь = require('path');
const Правила = require(путь.join(__dirname, '..', 'js', 'нарды-правила.js'));
const Бот = require(путь.join(__dirname, '..', 'js', 'нарды-бот.js'));
const Генератор = require(путь.join(__dirname, 'общий-генератор.js'));
const { порогПоНагрузке } = require('./утилита-порога-по-нагрузке.js');

/* --- границы, объявленные штабом до прогона --- */
const ПОРОГ_МАСТЕРА = 0.57;          // ниже — не сдаём
const ЦЕЛЬ_МАСТЕРА = 0.60;           // к чему стремимся
const ПОРОГ_ЛЕСТНИЦЫ = 0.55;         // «сложный» против «лёгкого»
const ПОТОЛОК_ХОДА_МС = 100;         // на Node; на телефоне это около 300
const ХОДОВ_МАКСИМУМ = 1000;         // дальше партия считается зависшей

/* --- разбор просьбы --- */
const слова = process.argv.slice(2);
const ломаем = слова.indexOf('--сломать') !== -1;
const числа = слова.filter(function (с) { return /^\d+$/.test(с); }).map(Number);
const ПАРТИЙ = Math.max(2, числа[0] || 500);
const ЗЕРНО = числа[1] || 20260915;
const ПАР = Math.ceil(ПАРТИЙ / 2);   // партии всегда идут парами: туда и обратно

/* Кого на самом деле сажаем за доску вместо мастера. При ломающем
   запуске это «сложный» — то есть соперник сам с собой. */
const УРОВЕНЬ_МАСТЕРА = ломаем ? 'сложный' : 'мастер';

/* =====================================================================
   ЧАСТЬ 1. ОДНА ПАРТИЯ
   ===================================================================== */

/** Кубик из потока: поток даёт число от 0 до 1, кубик — от 1 до 6. */
function кубик(поток) { return 1 + Math.floor(поток() * 6); }

/**
 * Партия двух уровней. Кубики берутся из потока с названным зерном —
 * значит, та же партия повторяется в точности.
 *
 * Возвращает, кто выиграл и сколько это стоило, либо беду: незаконный
 * ход или зависание. Беда — это провал турнира, а не строчка в отчёте.
 */
function партия(вид, зерно, уровеньБелых, уровеньЧёрных, замерыЗа) {
  const кубики = Генератор.создатьПоток(зерно);

  /* Тай-брейки ботов — свой поток, свой сдвиг зерна. Нужен отдельный,
     чтобы выбор из равных ходов не сдвигал последовательность кубиков:
     иначе в паре «туда и обратно» кубики разъехались бы, и весь смысл
     дуплирования пропал. */
  const родной = Math.random;
  Math.random = Генератор.создатьПоток(зерно + 1);

  try {
    const п = Правила.создатьПартию({ вид: вид, первый: Правила.БЕЛЫЕ });
    let ходов = 0;
    while (!Правила.партияЗавершена(п) && ходов < ХОДОВ_МАКСИМУМ) {
      Правила.бросить(п, [кубик(кубики), кубик(кубики)]);
      const чей = Правила.чейХод(п);
      const уровень = чей === Правила.БЕЛЫЕ ? уровеньБелых : уровеньЧёрных;

      const начало = Date.now();
      const ход = Бот.выбратьХод(п, уровень);
      const мс = Date.now() - начало;
      if (замерыЗа && уровень === замерыЗа) {
        замеры.сумма += мс;
        замеры.сколько++;
        if (мс > замеры.худшее) замеры.худшее = мс;
        замеры.все.push(мс);
      }

      if (ход) {
        /* Ход применяется ПОЛНОЙ дверью правил, с проверкой. Быстрая
           дверь здесь была бы неуместна: турнир как раз и обязан
           убедиться, что бот не предлагает ничего незаконного. */
        if (!Правила.сделатьХод(п, ход)) return { беда: 'бот предложил ход, который правила не приняли' };
      } else {
        if (!Правила.завершитьХод(п)) return { беда: 'ходов нет, а ход не передаётся' };
      }
      ходов++;
    }
    if (!Правила.партияЗавершена(п)) return { беда: 'партия не кончилась за ' + ХОДОВ_МАКСИМУМ + ' ходов' };
    const итог = Правила.итог(п);
    return { победитель: итог.победитель, цена: итог.цена, ходов: ходов };
  } finally {
    Math.random = родной;                          // чужую случайность возвращаем как было
  }
}

/* Замеры времени того уровня, который мы изучаем. Держатся снаружи,
   потому что копятся через весь турнир. */
const замеры = { сумма: 0, сколько: 0, худшее: 0, все: [] };

/* =====================================================================
   ЧАСТЬ 2. МАТЧ ДУПЛИРОВАННЫМИ КУБИКАМИ
   ===================================================================== */

/**
 * Матч уровня «А» против уровня «Б». Каждая пара партий играется одними
 * и теми же кубиками: сперва А белыми, потом Б белыми. Возвращает долю
 * побед А, очки обоих (марс — два, кокс — три) и среднюю длину партии.
 */
function матч(вид, уровеньА, уровеньБ, пар, мерим) {
  let победА = 0;
  let всего = 0;
  let очкиА = 0;
  let очкиБ = 0;
  let ходовВсего = 0;

  for (let н = 0; н < пар; н++) {
    const зерно = ЗЕРНО + н * 7919;                // 7919 — простое, чтобы зёрна не липли
    for (const аБелыми of [true, false]) {
      const итог = партия(вид, зерно,
        аБелыми ? уровеньА : уровеньБ,
        аБелыми ? уровеньБ : уровеньА,
        мерим);
      if (итог.беда) return { беда: итог.беда };
      всего++;
      ходовВсего += итог.ходов;
      const выигралА = (итог.победитель === Правила.БЕЛЫЕ) === аБелыми;
      if (выигралА) { победА++; очкиА += итог.цена; } else { очкиБ += итог.цена; }
    }
  }

  const доля = победА / всего;
  return {
    доля: доля,
    партий: всего,
    очкиА: очкиА,
    очкиБ: очкиБ,
    ходов: ходовВсего / всего,
    /* Размах, в который истина попадает с вероятностью 95 из 100. */
    размах: 1.96 * Math.sqrt(доля * (1 - доля) / всего)
  };
}

/* =====================================================================
   ЧАСТЬ 3. ПРОГОН И ОТЧЁТ
   ===================================================================== */

let проверок = 0;
let провалов = 0;

function проверить(название, условие, пояснение) {
  проверок++;
  if (условие) console.log('  ок     ' + название);
  else { провалов++; console.log('  ПРОВАЛ ' + название + (пояснение ? ' — ' + пояснение : '')); }
}

function процент(ч) { return (ч * 100).toFixed(1) + '%'; }

console.log('=== Турнир нард ===');
console.log('Партий в каждом матче: ' + (ПАР * 2) + ' (' + ПАР + ' пар дуплированными кубиками)');
console.log('Зерно: ' + ЗЕРНО);
if (ломаем) {
  console.log('');
  console.log('ЛОМАЮЩИЙ ЗАПУСК: вместо мастера играет тот же «сложный».');
  console.log('Соперники одинаковые, и проверка обязана покраснеть.');
}
console.log('');

/* --- матч первый: новый уровень против того, что стоит в игре --- */
console.log('1. Мастер против нынешнего «сложного» (цель ' + процент(ЦЕЛЬ_МАСТЕРА) +
  ', нижняя допустимая ' + процент(ПОРОГ_МАСТЕРА) + ')');

const главные = {};
for (const вид of [Правила.КОРОТКИЕ, Правила.ДЛИННЫЕ]) {
  const итог = матч(вид, УРОВЕНЬ_МАСТЕРА, 'сложный', ПАР, УРОВЕНЬ_МАСТЕРА);
  if (итог.беда) {
    проверить(вид + ': матч доигран', false, итог.беда);
    continue;
  }
  главные[вид] = итог;
  console.log('   ' + вид + ': ' + процент(итог.доля) + ' побед (±' + (итог.размах * 100).toFixed(1) +
    '), очки ' + итог.очкиА + ':' + итог.очкиБ + ', ходов в партии ' + итог.ходов.toFixed(0));
  проверить(вид + ': мастер берёт не меньше ' + процент(ПОРОГ_МАСТЕРА),
    итог.доля >= ПОРОГ_МАСТЕРА, 'вышло ' + процент(итог.доля));
}

/* --- матч второй: не сломали ли мы старую лестницу --- */
console.log('');
console.log('2. Старая лестница на месте: «сложный» против «лёгкого» (не ниже ' + процент(ПОРОГ_ЛЕСТНИЦЫ) + ')');
for (const вид of [Правила.КОРОТКИЕ, Правила.ДЛИННЫЕ]) {
  const итог = матч(вид, 'сложный', 'лёгкий', Math.max(75, Math.floor(ПАР / 2)), null);
  if (итог.беда) {
    проверить(вид + ': матч доигран', false, итог.беда);
    continue;
  }
  console.log('   ' + вид + ': ' + процент(итог.доля) + ' побед (±' + (итог.размах * 100).toFixed(1) +
    '), очки ' + итог.очкиА + ':' + итог.очкиБ);
  проверить(вид + ': «сложный» по-прежнему обыгрывает «лёгкого»',
    итог.доля >= ПОРОГ_ЛЕСТНИЦЫ, 'вышло ' + процент(итог.доля));
}

/* --- время --- */
console.log('');
console.log('3. Время на ход (' + замеры.сколько + ' ходов обдумано)');
console.log('   в среднем ' + (замеры.сумма / Math.max(замеры.сколько, 1)).toFixed(1) +
  ' мс, худший ход ' + замеры.худшее + ' мс');

/* Вычисляем 99-й перцентиль: показывает, что 99% ходов укладываются в лимит,
   без реакции на редкие выбросы от GC или JIT. */
let перцентиль99 = 0;
if (замеры.сколько > 0) {
  const отсортировано = замеры.все.slice().sort(function(a, b) { return a - b; });
  const индекс = Math.ceil(0.99 * отсортировано.length) - 1;
  перцентиль99 = отсортировано[Math.max(0, индекс)];
}
console.log('   99-й перцентиль ' + перцентиль99 + ' мс');

const потолокСейчас = порогПоНагрузке(ПОТОЛОК_ХОДА_МС);
проверить('99-й перцентиль времени хода не превышает ' + потолокСейчас + ' мс (база ' + ПОТОЛОК_ХОДА_МС + ')',
  перцентиль99 <= потолокСейчас, '99-й перцентиль ' + перцентиль99 + ' мс');

/* --- цель, отдельной строкой: её невыполнение не провал, а повод думать --- */
console.log('');
console.log('4. Дошли ли до цели в ' + процент(ЦЕЛЬ_МАСТЕРА));
for (const вид of [Правила.КОРОТКИЕ, Правила.ДЛИННЫЕ]) {
  const итог = главные[вид];
  if (!итог) continue;
  const дошли = итог.доля >= ЦЕЛЬ_МАСТЕРА;
  console.log('   ' + вид + ': ' + процент(итог.доля) + ' — ' +
    (дошли ? 'цель взята' : 'до цели не хватило ' + процент(ЦЕЛЬ_МАСТЕРА - итог.доля) +
      ', но нижняя граница ' + (итог.доля >= ПОРОГ_МАСТЕРА ? 'взята' : 'НЕ взята')));
}

/* =====================================================================
   ИТОГ
   ===================================================================== */

console.log('');
console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);

if (ломаем) {
  /* При ломающем запуске провалы — это успех: значит, турнир умеет
     краснеть и зелёному отчёту в обычный день можно верить. */
  if (провалов > 0) {
    console.log('Ломающий запуск: проверка покраснела, как и должна. Ей можно верить.');
    process.exitCode = 0;
  } else {
    console.log('ЛОМАЮЩИЙ ЗАПУСК ПРОШЁЛ ЗЕЛЁНЫМ — проверка не краснеет, верить ей нельзя.');
    process.exitCode = 1;
  }
} else {
  process.exitCode = провалов ? 1 : 0;
}
