'use strict';

/**
 * Адаптирует временной порог проверки к текущей нагрузке машины.
 *
 * Проблема: проверки сравнивают время с жёсткими порогами, снятыми на свободной
 * машине. При нагрузке реальное время выше, и проверки ложно краснеют.
 *
 * Решение: замер текущей нагрузки простым CPU-bound циклом и растяжка порога.
 */

/* =====================================================================
   ЭТАЛОННАЯ КОНСТАНТА КАЛИБРОВКИ — снята на этой машине 2026-09-18

   Замер: цикл из 10 000 000 итераций (let i = 0; i < 10000000; i++)
   с операцией сумма += i внутри, прогон 3 раза, среднее ~60 мс.

   Эта константа используется для вычисления коэффициента нагрузки:
   если машина СЕЙЧАС замеряется дольше, то коэффициент > 1, порог растягивается.
   ===================================================================== */
const ЭТАЛОННОЕ_ВРЕМЯ_МС = 60;
const КАЛИБРОВОЧНЫХ_ИТЕРАЦИЙ = 10000000;

/**
 * Вычисляет коэффициент нагрузки машины прямо сейчас.
 * Возвращает число ≥ 1: 1 = машина быстра, 2 = медленнее в два раза и т.д.
 *
 * @returns {number}
 */
function коэффициентНагрузки() {
  const начало = Date.now();
  let сумма = 0;
  for (let i = 0; i < КАЛИБРОВОЧНЫХ_ИТЕРАЦИЙ; i++) {
    сумма += i;
  }
  const прошло = Date.now() - начало;

  // Коэффициент не должен снижать порог ниже базового — иначе проверка
  // перестанет ловить проблемы, даже если машина чуть быстрее эталона.
  return Math.max(1, прошло / ЭТАЛОННОЕ_ВРЕМЯ_МС);
}

/**
 * Адаптирует базовый порог (мс) к текущей нагрузке машины.
 *
 * Если машина медленнее, чем была при калибровке, порог растягивается.
 * Если быстрее — порог остаётся базовым (не сокращается).
 *
 * @param {number} базовыйПорогМс — эталонный порог в мс (снят на свободной машине)
 * @returns {number} порог с поправкой на нагрузку
 */
function порогПоНагрузке(базовыйПорогМс) {
  const коэф = коэффициентНагрузки();
  return Math.round(базовыйПорогМс * коэф);
}

// ===== Самозапуск — демонстрация =====
if (require.main === module) {
  console.log('Коэффициент нагрузки и растяжка порогов\n');

  const коэф = коэффициентНагрузки();
  console.log('Коэффициент нагрузки машины: ' + коэф.toFixed(2) + 'x');
  console.log('(1.0 = машина как при калибровке, > 1 = медленнее)\n');

  const примеры = [
    { база: 25, описание: 'обычный кадр (25 мс)' },
    { база: 40, описание: 'на слабом телефоне (40 мс)' },
    { база: 150, описание: 'базовый порог для колоды 36 карт (150 мс)' }
  ];

  console.log('Примеры растяжки порогов:\n');
  примеры.forEach(({ база, описание }) => {
    const растянутый = порогПоНагрузке(база);
    console.log(`  ${описание}`);
    console.log(`    базовый:   ${база} мс`);
    console.log(`    адаптирован: ${растянутый} мс`);
    console.log();
  });
}

module.exports = { порогПоНагрузке, коэффициентНагрузки };
