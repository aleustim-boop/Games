'use strict';
/* =====================================================================
   СЕСТЬ ЗА СТОЛ ДУРАКА — один помощник на все проверки.

   Зачем. 11 сентября у дурака вместо прежнего меню («Играть с ботом»,
   экран «Игра с ботом» с тремя рядами кнопок) появились лобби и три шага
   по макетам владельца. Прежние узлы (#экран-меню, #экран-бота,
   #кнопка-режим-бот, #меню-выбор-мест …) удалены, а три с половиной
   десятка проверок входили за стол именно через них — каждая своими
   строчками. Теперь дорога за стол описана ОДИН раз, здесь: поменяется
   путь снова — править одно место, а не тридцать четыре.

   ДОРОГА ЧЕЛОВЕКА: витрина → «Дурак» (#кнопка-игра-дурак) → лобби
   (#экран-лобби) → «Играть с ботами» (#лобби-боты) → шаг 1 «Правила» →
   «Далее» → шаг 2 «Игроки» → «Далее» → шаг 3 «Настройки» → «Начать игру»
   (#путь-начать) → стол (#экран-игры). «Далее» есть на всех трёх шагах,
   поэтому искать его можно только на видимом экране.

   ЧТО ДАЁТ:
     • в Node, для стендов на playwright (страница — объект playwright):
         сестьЗаСтол(страница, настройки)  — настоящими нажатиями по дороге
                                            человека, с выбором стола;
         сестьБезНажатий(страница, настройки) — сразу за стол: ИграСБотами
                                            и начатьПартию() (для замеров,
                                            которым дорога не важна);
         вЛобби(страница)                   — с витрины (или откуда угодно
                                            внутри index.html) в лобби;
         открытьЛист(страница)              — лист «⋯» видимого экрана: кнопкой,
                                            а в Telegram — пунктом «Настройки»;
         открытьРекорды(страница)           — лобби → «⋯» → «Рекорды»;
         КОД_ДЛЯ_СТРАНИЦЫ                   — исходник этого файла для
                                            addScriptTag({ content }).
     • в самой странице (файл вставлен в неё — addScriptTag или fetch+eval
       из кода для страницы): window.СестьЗаСтол с теми же делами —
         нажатиями(настройки), безНажатий(настройки), вЛобби(),
         открытьРекорды(). Здесь «нажатие» — element.click(): у кода,
         живущего в странице, другого пальца нет.

   НАСТРОЙКИ (всё необязательно; чего не назвали — остаётся как выбрано):
     игроков: 2…6        — «Всего игроков», шаг 2;
     парами: true/false  — формат «2 на 2» / «Каждый за себя», шаг 2;
     переводной: true/false — «Переводной» / «Подкидной», шаг 1;
     сложность: 'лёгкий' | 'обычный' | 'сложный' — шаг 3 («Легко»…);
     колода: 36 | 52     — шаг 3.
   Вариант выключен (например, 36 карт на шестерых) — помощник не жмёт
   вслепую, а бросает ошибку со словами игры «почему нельзя».

   Скрытая «#кнопка-играть» осталась в лобби дверью для js/сеть.js. Жать её
   можно только element.click(): нажатие playwright по скрытой кнопке
   падает, а «нажать, если видна» её молча пропускает — и проверка стоит
   на лобби, думая, что сидит за столом.
   ===================================================================== */
(function () {
  const ПОДПИСИ_СЛОЖНОСТИ = { 'лёгкий': 'Легко', 'обычный': 'Средне', 'сложный': 'Сложно' };

  /* ---------------------------------------------------------------------
     Часть для страницы. Работает внутри index.html, ничего не знает про
     playwright. Её же исходник уходит в страницу из Node — одна копия шагов.
     --------------------------------------------------------------------- */
  function сделатьДляСтраницы(окно) {
    const документ = окно.document;
    const ждать = (мс) => new Promise((г) => setTimeout(г, мс));
    const видимый = () => {
      const э = документ.querySelector('.экран.экран--виден');
      return э ? э.id : '';
    };
    async function дождаться(экран, мс) {
      const край = Date.now() + (мс || 4000);
      while (Date.now() < край) {
        if (видимый() === экран) return true;
        await ждать(40);
      }
      throw new Error('СестьЗаСтол: не дождались экрана «' + экран + '», видно «' + видимый() + '»');
    }
    function нажать(узел, что) {
      if (!узел) throw new Error('СестьЗаСтол: не нашёл «' + что + '»');
      if (узел.disabled) {
        const почему = узел.getAttribute('title') || узел.getAttribute('aria-description') || '';
        throw new Error('СестьЗаСтол: «' + что + '» выключено' + (почему ? ' — ' + почему : ''));
      }
      узел.click();
    }
    const поТексту = (выбор, образец) => Array.from(документ.querySelectorAll(выбор))
      .find((у) => образец.test((у.textContent || '').trim()));

    async function вЛобби() {
      if (видимый() === 'экран-лобби') return;
      if (видимый() === 'экран-витрины') нажать(документ.getElementById('кнопка-игра-дурак'), 'Дурак на витрине');
      else if (typeof окно.показатьЛоббиДурака === 'function') окно.показатьЛоббиДурака();
      await дождаться('экран-лобби');
    }

    async function нажатиями(настройки) {
      const н = настройки || {};
      await вЛобби();
      нажать(документ.getElementById('лобби-боты'), 'Играть с ботами');
      await дождаться('экран-путь-правила');
      if (typeof н.переводной === 'boolean') {
        нажать(документ.querySelector('#путь-правила-варианты [data-вариант="' + (н.переводной ? 'переводной' : 'подкидной') + '"]'),
          н.переводной ? 'Переводной' : 'Подкидной');
      }
      нажать(документ.querySelector('.экран.экран--виден [data-путь="далее"]'), 'Далее на шаге 1');
      await дождаться('экран-путь-игроки');
      if (typeof н.парами === 'boolean') {
        const форматы = документ.querySelectorAll('#путь-форматы .переключатель__вариант');
        нажать(форматы[н.парами ? 1 : 0], н.парами ? '2 на 2' : 'Каждый за себя');
      }
      if (н.игроков) {
        нажать(поТексту('#путь-числа .числа__число', new RegExp('^' + н.игроков + '$')), 'игроков: ' + н.игроков);
      }
      нажать(документ.querySelector('.экран.экран--виден [data-путь="далее"]'), 'Далее на шаге 2');
      await дождаться('экран-путь-настройки');
      if (н.колода) нажать(поТексту('#путь-колоды .переключатель__вариант', new RegExp('^' + н.колода)), 'колода ' + н.колода);
      if (н.сложность) {
        const подпись = ПОДПИСИ_СЛОЖНОСТИ[н.сложность] || н.сложность;
        нажать(поТексту('#путь-сложность .переключатель__вариант', new RegExp('^' + подпись + '$')), 'сложность ' + подпись);
      }
      нажать(документ.getElementById('путь-начать'), 'Начать игру');
      await дождаться('экран-игры');
      return сводкаПартии();
    }

    async function безНажатий(настройки) {
      const н = настройки || {};
      const стол = окно.ИграСБотами;
      if (!стол || typeof окно.начатьПартию !== 'function') throw new Error('СестьЗаСтол: нет ИграСБотами или начатьПартию');
      if (н.игроков) стол.игроков = н.игроков;
      if (typeof н.парами === 'boolean') стол.парами = н.парами;
      if (typeof н.переводной === 'boolean') стол.переводной = н.переводной;
      if (н.колода) стол.колода = н.колода;
      /* Уровень живёт не в ИграСБотами, а в общей переменной «сложность»
         js/game.js (её же меняют шаги пути). До неё достаёт только eval. */
      if (н.сложность) окно.eval('сложность = ' + JSON.stringify(н.сложность));
      окно.начатьПартию();
      await дождаться('экран-игры');
      return сводкаПартии();
    }

    async function открытьРекорды() {
      await вЛобби();
      /* Кнопку «⋯» жмём даже спрятанную (в Telegram строка скрыта): у кода
         в странице «нажатие» — это element.click(), видимость ему не нужна. */
      нажать(документ.querySelector('#экран-лобби [data-путь="ещё"]'), '⋯ в лобби');
      await ждать(80);
      нажать(документ.getElementById('кнопка-лист-игры-рекорды'), 'Рекорды в листе');
      await дождаться('экран-рекордов');
    }

    function сводкаПартии() {
      const п = окно.eval('typeof партия !== "undefined" ? партия : null');
      if (!п) return null;
      return { игроков: п.игроки.length, переводной: Boolean(п.переводной), парами: Boolean(п.парами),
               сложность: п.сложность, колода: п.размерКолоды };
    }

    return { нажатиями, безНажатий, вЛобби, открытьРекорды, сводкаПартии, видимый };
  }

  /* В странице — сразу кладём дверь. */
  if (typeof window !== 'undefined' && typeof document !== 'undefined') {
    window.СестьЗаСтол = сделатьДляСтраницы(window);
  }

  /* ---------------------------------------------------------------------
     Часть для Node: стенды на playwright. Нажатия — настоящие, по видимым
     узлам; дверь в странице ставим тем же файлом, что и выше.
     --------------------------------------------------------------------- */
  if (typeof module !== 'undefined' && module.exports) {
    const fs = require('fs');
    const путьК = require('path');
    const КОД_ДЛЯ_СТРАНИЦЫ = fs.readFileSync(путьК.join(__dirname, 'сесть-за-стол.js'), 'utf8');

    async function видимыйЭкран(страница) {
      return страница.evaluate(() => {
        const э = document.querySelector('.экран.экран--виден');
        return э ? э.id : '';
      });
    }

    async function дождаться(страница, экран, мс) {
      try {
        await страница.waitForFunction((и) => {
          const э = document.querySelector('.экран.экран--виден');
          return Boolean(э && э.id === и);
        }, экран, { timeout: мс || 6000 });
      } catch (ошибка) {
        throw new Error('сестьЗаСтол: не дождались экрана «' + экран + '», видно «' + await видимыйЭкран(страница) + '»');
      }
    }

    /** Нажать видимый узел; выключенный — ошибка со словами игры, а не долгое ожидание. */
    async function нажать(страница, локатор, что) {
      const сколько = await локатор.count();
      if (!сколько) throw new Error('сестьЗаСтол: не нашёл «' + что + '»');
      const первый = локатор.first();
      if (await первый.isDisabled()) {
        const почему = (await первый.getAttribute('title')) || '';
        throw new Error('сестьЗаСтол: «' + что + '» выключено' + (почему ? ' — ' + почему : ''));
      }
      await первый.click({ timeout: 5000 });
    }

    async function вЛобби(страница) {
      const где = await видимыйЭкран(страница);
      if (где === 'экран-лобби') return;
      if (где === 'экран-витрины') await нажать(страница, страница.locator('#кнопка-игра-дурак'), 'Дурак на витрине');
      else await страница.evaluate(() => { if (typeof показатьЛоббиДурака === 'function') показатьЛоббиДурака(); });
      await дождаться(страница, 'экран-лобби');
    }

    async function сестьЗаСтол(страница, настройки) {
      const н = настройки || {};
      await вЛобби(страница);
      await нажать(страница, страница.locator('#лобби-боты'), 'Играть с ботами');
      await дождаться(страница, 'экран-путь-правила');
      if (typeof н.переводной === 'boolean') {
        await нажать(страница, страница.locator('#путь-правила-варианты [data-вариант="' + (н.переводной ? 'переводной' : 'подкидной') + '"]'),
          н.переводной ? 'Переводной' : 'Подкидной');
      }
      await нажать(страница, страница.locator('.экран.экран--виден [data-путь="далее"]'), 'Далее на шаге 1');
      await дождаться(страница, 'экран-путь-игроки');
      if (typeof н.парами === 'boolean') {
        await нажать(страница, страница.locator('#путь-форматы .переключатель__вариант').nth(н.парами ? 1 : 0), н.парами ? '2 на 2' : 'Каждый за себя');
      }
      if (н.игроков) {
        await нажать(страница, страница.locator('#путь-числа .числа__число', { hasText: new RegExp('^\\s*' + н.игроков + '\\s*$') }), 'игроков: ' + н.игроков);
      }
      await нажать(страница, страница.locator('.экран.экран--виден [data-путь="далее"]'), 'Далее на шаге 2');
      await дождаться(страница, 'экран-путь-настройки');
      if (н.колода) {
        await нажать(страница, страница.locator('#путь-колоды .переключатель__вариант', { hasText: new RegExp('^\\s*' + н.колода) }), 'колода ' + н.колода);
      }
      if (н.сложность) {
        const подпись = ПОДПИСИ_СЛОЖНОСТИ[н.сложность] || н.сложность;
        await нажать(страница, страница.locator('#путь-сложность .переключатель__вариант', { hasText: new RegExp('^\\s*' + подпись + '\\s*$') }), 'сложность ' + подпись);
      }
      await нажать(страница, страница.locator('#путь-начать'), 'Начать игру');
      await дождаться(страница, 'экран-игры');
      return сводкаПартии(страница);
    }

    async function сестьБезНажатий(страница, настройки) {
      await страница.waitForFunction(() => typeof window.ИграСБотами !== 'undefined' && typeof начатьПартию === 'function');
      await страница.evaluate((н) => {
        const стол = window.ИграСБотами;
        if (н.игроков) стол.игроков = н.игроков;
        if (typeof н.парами === 'boolean') стол.парами = н.парами;
        if (typeof н.переводной === 'boolean') стол.переводной = н.переводной;
        if (н.колода) стол.колода = н.колода;
        // Уровень — общая переменная js/game.js, не поле ИграСБотами.
        if (н.сложность) сложность = н.сложность;   // eslint-disable-line no-undef
        начатьПартию();
      }, настройки || {});
      await дождаться(страница, 'экран-игры');
      return сводкаПартии(страница);
    }

    /**
     * Открыть лист «⋯» на видимом экране (лобби, шаг, стол), как человек:
     * вне Telegram — кнопкой «⋯» в верхней строке; в Telegram эта строка
     * спрятана оформлением, и лист зовут пунктом «Настройки» его меню
     * (у поддельного Telegram — ПоддельныйТелеграм.нажатьНастройки()).
     * Вернёт, чем открыли.
     */
    async function открытьЛист(страница) {
      const кнопка = страница.locator('.экран.экран--виден [data-путь="ещё"], #экран-игры.экран--виден #кнопка-игра-ещё');
      if (await кнопка.count() && await кнопка.first().isVisible()) {
        await кнопка.first().click({ timeout: 5000 });
        return 'кнопкой «⋯»';
      }
      const чем = await страница.evaluate(() => {
        if (window.ПоддельныйТелеграм && typeof window.ПоддельныйТелеграм.нажатьНастройки === 'function') {
          window.ПоддельныйТелеграм.нажатьНастройки();
          return 'пунктом «Настройки» Telegram';
        }
        return '';
      });
      const открыт = await страница.evaluate(() => {
        const лист = document.getElementById('лист-игры');
        return Boolean(лист && !лист.classList.contains('скрыт'));
      });
      if (!открыт) throw new Error('сестьЗаСтол: лист «⋯» не открылся (' + (чем || 'ни кнопки, ни пункта «Настройки»') + ')');
      return чем;
    }

    async function открытьРекорды(страница) {
      await вЛобби(страница);
      await открытьЛист(страница);
      await нажать(страница, страница.locator('#кнопка-лист-игры-рекорды'), 'Рекорды в листе');
      await дождаться(страница, 'экран-рекордов');
    }

    function сводкаПартии(страница) {
      return страница.evaluate(() => {
        if (typeof партия === 'undefined' || !партия) return null;
        return { игроков: партия.игроки.length, переводной: Boolean(партия.переводной), парами: Boolean(партия.парами),
                 сложность: партия.сложность, колода: партия.размерКолоды };
      });
    }

    module.exports = { сестьЗаСтол, сестьБезНажатий, вЛобби, открытьЛист, открытьРекорды, видимыйЭкран, сводкаПартии, КОД_ДЛЯ_СТРАНИЦЫ };
  }
})();
