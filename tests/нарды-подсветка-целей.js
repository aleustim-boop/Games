/* ---------------------------------------------------------------------
   ЛОМАЮЩИЙ ЗАПУСК --сломать-выделение: портим КОПИЮ style-нарды.css во
   временной папке — отменяем ровно три правки 24.09, которые делают
   выбранную шашку заметной и не дают метке цели прятаться под фишкой:
     1) z-index поднятой шашки возвращаем с 5 на 4 (снова тонет в стопке);
     2) кольцо выбора снова гасим до «opacity: 0» (снова невидимо);
     3) z-index метки цели возвращаем с 5 на 2 (снова прячется под фишкой).
   Каждая замена проверяется отдельно — «ноль найденного» останавливает
   ломающий запуск с ошибкой, а не тихо портит меньше, чем задумано.
   --------------------------------------------------------------------- */
function приготовитьИспорченнуюКопиюВыделения() {
  const путьКФайлу = path.join(КОРЕНЬ, 'style-нарды.css');
  let исходник = fs.readFileSync(путьКФайлу, 'utf8');
  const замены = [
    {
      было: '.пункт > .шашка.шашка--поднята,\n.бар__половина > .шашка.шашка--поднята {\n  z-index: 5;\n}',
      стало: '.пункт > .шашка.шашка--поднята,\n.бар__половина > .шашка.шашка--поднята {\n  z-index: 4;\n}',
      слова: 'z-index поднятой шашки'
    },
    {
      было: '.шашка--поднята > .шашка__кольцо { opacity: 1; }',
      стало: '.шашка--поднята > .шашка__кольцо { opacity: 0; }',
      слова: 'видимость кольца выбора'
    },
    {
      было: '  z-index: 5;\n  opacity: 0;\n  pointer-events: none;\n  --слой-цели: var(--шашек, 0);',
      стало: '  z-index: 2;\n  opacity: 0;\n  pointer-events: none;\n  --слой-цели: var(--шашек, 0);',
      слова: 'z-index метки цели'
    }
  ];
  for (const замена of замены) {
    if (!исходник.includes(замена.было)) {
      console.error('ломающий запуск --сломать-выделение сломался: в style-нарды.css не нашлось ' +
        'ожидаемое правило «' + замена.слова + '» — ноль замен, портить нечего (провал, а не пропуск)');
      process.exit(2);
    }
    исходник = исходник.replace(замена.было, замена.стало);
  }
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'нарды-выделение-'));
  const копия = path.join(папка, 'style-нарды.css');
  fs.writeFileSync(копия, исходник, 'utf8');
  console.log('ломающий запуск --сломать-выделение: испорченная копия лежит в ' + копия);
  return { копия, папка };
}

