/* =====================================================================
   ПОДСВЕТКА ЦЕЛЕЙ В НАРДАХ (нарды.html, js/нарды-экран.js).

   Жалоба новичка-плейтестера: выбрал шашку — появляется общая фраза
   «Выберите, куда пойти», но КОНКРЕТНЫЕ пункты-цели не подсвечены
   точками, как в шашках и шахматах — непонятно, куда тапать. А если
   промахнуться мимо цели — выбор молча сбрасывается без единого слова,
   закономерность объяснения не поймать.

   Проверка идёт настоящей игрой: заходит вдвоём на одном устройстве,
   бросает кубики по-настоящему (случайный бросок, кубики не подделываем —
   после броска смотрим на DOM, а не предсказываем цифры заранее), берёт
   первую шашку, которой есть куда пойти, и проверяет два места:

     1) после выбора шашки КАЖДЫЙ пункт-цель подсвечен классом
        «пункт--можно» и виден по-настоящему — не просто есть в DOM с
        нулевой непрозрачностью, а посчитанный браузером стиль
        (getComputedStyle) не прозрачный и не нулевого размера;
     2) клик по заведомо недопустимому пункту (пустому или занятому
        соперником — то есть НЕ своей шашкой, иначе это было бы простое
        перекладывание руки) даёт непустую строку в «подсказка-хода», а
        не тихий сброс выбора.

   Раздачу страниц поднимаем сами на свободном порту, второй процесс не
   заводим, зависимость только от файлов проекта.

   Запуск:
       node tests/нарды-подсветка-целей.js
   Ломающий запуск №1 — про объяснение промаха (обязан покраснеть):
   раздача отдаёт вместо настоящего js/нарды-экран.js его КОПИЮ из
   временной папки, где строка после промаха возвращена к старому,
   молчаливому виду (объяснитьОтказ(место) вместо
   сказатьСловами(причинаНеверногоНазначения(...))). Файл проекта не
   трогаем и не откатываем — портим только копию:
       node tests/нарды-подсветка-целей.js --сломать
   Ломающий запуск №2 — про саму видимость подсветки (обязан покраснеть):
   раздача отдаёт вместо настоящего style-нарды.css его КОПИЮ, где
   правило «.пункт--можно > .пункт__цель { opacity: 1; ... }» снова
   «opacity: 0» — метка в DOM есть, а видно её не будет. Файл проекта не
   трогаем:
       node tests/нарды-подсветка-целей.js --сломать-вид

   Написано разработчиком по заданию штаба, живёт в tests/.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const os = require('os');
const http = require('http');
const { chromium, подготовитьПодделку } = require('./браузер-робот.js');

const КОРЕНЬ = path.join(__dirname, '..');
const СЛОМАТЬ = process.argv.includes('--сломать');
const СЛОМАТЬ_ВИД = process.argv.includes('--сломать-вид');

let всегоПроверок = 0;
let провалов = 0;
function проверить(условие, слова) {
  всегоПроверок++;
  if (условие) console.log('  ок   — ' + слова);
  else { провалов++; console.log('  ПЛОХО— ' + слова); }
}
const ТИПЫ = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.mp3': 'audio/mpeg'
};

/** Раздача файлов проекта на свободном порту (карта «подмены» — для ломающих запусков). */
function поднятьРаздачу(подмены) {
  const карта = подмены || {};
  const сервер = http.createServer(function (запрос, ответ) {
    let путь = запрос.url.split('?')[0].split('#')[0];
    try { путь = decodeURIComponent(путь); } catch (ошибка) { /* оставим как есть */ }
    const файл = карта[путь] || path.join(КОРЕНЬ, путь === '/' ? 'нарды.html' : путь.slice(1));
    fs.readFile(файл, function (беда, тело) {
      if (беда) { ответ.writeHead(404); ответ.end('нет такого файла'); return; }
      ответ.writeHead(200, { 'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'text/plain' });
      ответ.end(тело);
    });
  });
  return new Promise((готово) => сервер.listen(0, '127.0.0.1', () => готово(сервер)));
}

/* ---------------------------------------------------------------------
   ЛОМАЮЩИЙ ЗАПУСК --сломать: портим КОПИЮ js/нарды-экран.js во временной
   папке — возвращаем ветку промаха к старому молчаливому виду.
   --------------------------------------------------------------------- */
function приготовитьИспорченнуюКопиюЭкрана() {
  const путьКФайлу = path.join(КОРЕНЬ, 'js', 'нарды-экран.js');
  const исходник = fs.readFileSync(путьКФайлу, 'utf8');
  const образецБыло = 'сказатьСловами(причинаНеверногоНазначения(источникДоПромаха, место));';
  const стало = 'объяснитьОтказ(место);';
  if (!исходник.includes(образецБыло)) {
    console.error('ломающий запуск --сломать сломался: в js/нарды-экран.js не нашлась ожидаемая ' +
      'строка объяснения промаха — ноль замен, портить нечего (провал, а не пропуск)');
    process.exit(2);
  }
  const испорченный = исходник.replace(образецБыло, стало);
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'нарды-промах-'));
  const копия = path.join(папка, 'нарды-экран.js');
  fs.writeFileSync(копия, испорченный, 'utf8');
  console.log('ломающий запуск --сломать: испорченная копия лежит в ' + копия);
  return { копия, папка };
}

/* ---------------------------------------------------------------------
   ЛОМАЮЩИЙ ЗАПУСК --сломать-вид: портим КОПИЮ style-нарды.css во
   временной папке — метка цели снова прозрачна даже там, где класс
   «пункт--можно» уже стоит.
   --------------------------------------------------------------------- */
function приготовитьИспорченнуюКопиюВида() {
  const путьКФайлу = path.join(КОРЕНЬ, 'style-нарды.css');
  const исходник = fs.readFileSync(путьКФайлу, 'utf8');
  const образецБыло = '.пункт--можно > .пункт__цель,\n.полка.пункт--можно > .пункт__цель {\n  opacity: 1;';
  const стало = '.пункт--можно > .пункт__цель,\n.полка.пункт--можно > .пункт__цель {\n  opacity: 0;';
  if (!исходник.includes(образецБыло)) {
    console.error('ломающий запуск --сломать-вид сломался: в style-нарды.css не нашлось ожидаемое ' +
      'правило видимости метки цели — ноль замен, портить нечего (провал, а не пропуск)');
    process.exit(2);
  }
  const испорченный = исходник.replace(образецБыло, стало);
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'нарды-вид-'));
  const копия = path.join(папка, 'style-нарды.css');
  fs.writeFileSync(копия, испорченный, 'utf8');
  console.log('ломающий запуск --сломать-вид: испорченная копия лежит в ' + копия);
  return { копия, папка };
}

function собратьОшибки(страница) {
  const ошибки = [];
  страница.on('pageerror', (о) => ошибки.push('исключение: ' + о.message));
  страница.on('console', (с) => {
    if (с.type() === 'error' && /Failed to load resource/.test(с.text())) return;
    if (с.type() === 'error') ошибки.push('консоль: ' + с.text());
  });
  return ошибки;
}

function отчётПоОшибкам(ошибки, слова) {
  return слова + (ошибки.length ? ' — а они есть: ' + ошибки.join(' | ') : '');
}

(async () => {
  const испорченныйЭкран = СЛОМАТЬ ? приготовитьИспорченнуюКопиюЭкрана() : null;
  const испорченныйВид = СЛОМАТЬ_ВИД ? приготовитьИспорченнуюКопиюВида() : null;
  const подменыФайлов = {};
  if (испорченныйЭкран) подменыФайлов['/js/нарды-экран.js'] = испорченныйЭкран.копия;
  if (испорченныйВид) подменыФайлов['/style-нарды.css'] = испорченныйВид.копия;
  const раздача = await поднятьРаздачу(Object.keys(подменыФайлов).length ? подменыФайлов : null);
  const ПОРТ = раздача.address().port;
  const АДРЕС = 'http://127.0.0.1:' + ПОРТ + '/нарды.html';
  console.log('раздача поднята: ' + АДРЕС +
    (СЛОМАТЬ ? '  (ЛОМАЮЩИЙ ЗАПУСК --сломать)' : '') +
    (СЛОМАТЬ_ВИД ? '  (ЛОМАЮЩИЙ ЗАПУСК --сломать-вид)' : ''));

  const браузер = await chromium.launch();
  const окно = await браузер.newContext({ viewport: { width: 390, height: 844 } });
  const страница = await окно.newPage();
  const ошибки = собратьОшибки(страница);
  await подготовитьПодделку(страница, { версия: '7.10' });
  await страница.goto(АДРЕС);
  await страница.waitForTimeout(400);

  console.log('\n=== 1. Вдвоём на одном устройстве: партия начинается, кубики бросаются ===');
  await страница.click('#лобби-вдвоём');
  await страница.waitForTimeout(400);
  const столВиден = await страница.evaluate(() =>
    document.getElementById('экран-игры').classList.contains('экран--виден'));
  проверить(столВиден, '«Вдвоём на этом устройстве» открыла стол партии');

  await страница.click('#кнопка-бросить');
  await страница.waitForTimeout(1200);

  const шашкаМожноИмя = await страница.evaluate(() => {
    const ш = document.querySelector('.шашка--можно-взять');
    return ш ? ш.dataset.шашка : null;
  });
  проверить(Boolean(шашкаМожноИмя), 'после броска на доске нашлась своя шашка, которой есть куда пойти');
  if (!шашкаМожноИмя) {
    console.error('дальше проверять нечем — партия не дала ходов, обрываем честным провалом');
    await браузер.close();
    раздача.close();
    console.log('\nИтого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
    process.exit(1);
  }

  console.log('\n=== 2. Выбор шашки подсвечивает КАЖДУЮ цель заметно, не только в разметке ===');
  // Клик — отдельным вызовом, БЕЗ немедленного чтения стиля следом же:
  // «пункт__цель» видна через CSS-переход (transition: opacity 0.14s),
  // а снятый в тот же тик getComputedStyle застаёт его в самой первой
  // точке (t=0), где opacity ещё честно равен нулю — это гонка в самой
  // проверке, не баг игры. Даём кадру дорисоваться отдельным ожиданием.
  await страница.evaluate((имя) => {
    const шашка = document.querySelector('.шашка[data-шашка="' + имя + '"]');
    const пункт = шашка.closest('.пункт, .бар__половина');
    пункт.dispatchEvent(new MouseEvent('click', { bubbles: true }));
  }, шашкаМожноИмя);
  await страница.waitForTimeout(220);

  const источникИнфо = await страница.evaluate(() => {
    const выбран = document.querySelector('.пункт--выбран');
    const поднятая = выбран ? выбран.querySelector('.шашка--поднята') : null;
    return {
      выбралось: Boolean(выбран),
      цвет: поднятая ? (поднятая.classList.contains('шашка--белая') ? 'белая' : 'чёрная') : null
    };
  });
  проверить(источникИнфо.выбралось, 'клик по пункту с ходкой шашкой поднимает её (класс «пункт--выбран»)');

  const подсказкаВыбора = await страница.evaluate(() =>
    (document.getElementById('подсказка-хода').textContent || '').trim());
  проверить(Boolean(подсказкаВыбора), 'после выбора шашки строка подсказки не пустая (получили: «' + подсказкаВыбора + '»)');

  // «Ноль найденных узлов — провал, а не пропуск»: если целей нет вовсе,
  // это и есть сама жалоба плейтестера, а не повод молча пропустить шаг.
  const целиИВид = await страница.evaluate(() => {
    const цели = Array.from(document.querySelectorAll('.пункт--можно, .полка.пункт--можно'));
    return цели.map((п) => {
      const метка = п.querySelector('.пункт__цель');
      if (!метка) return { пункт: п.dataset.пункт || п.className, естьМетка: false };
      const cs = getComputedStyle(метка);
      const прямоугольник = метка.getBoundingClientRect();
      return {
        пункт: п.dataset.пункт || п.className,
        естьМетка: true,
        opacity: parseFloat(cs.opacity),
        display: cs.display,
        visibility: cs.visibility,
        ширина: прямоугольник.width,
        высота: прямоугольник.height
      };
    });
  });
  console.log('  целей подсвечено: ' + целиИВид.length);
  проверить(целиИВид.length >= 1, 'после выбора шашки подсвечен хотя бы один пункт-цель (класс «пункт--можно»)');
  const всеВидны = целиИВид.length > 0 && целиИВид.every((ц) =>
    ц.естьМетка && ц.opacity > 0 && ц.display !== 'none' && ц.visibility !== 'hidden' &&
    ц.ширина > 0 && ц.высота > 0);
  проверить(всеВидны, 'КАЖДАЯ подсвеченная цель видна по-настоящему (opacity>0, не «none»/«hidden», есть размер) — ' +
    JSON.stringify(целиИВид));

  const папкаСнимков = path.join(КОРЕНЬ, 'tests', 'снимки');
  await fs.promises.mkdir(папкаСнимков, { recursive: true });
  const файлСнимка = path.join(папкаСнимков, 'нарды-подсветка-целей-390.png');
  await страница.screenshot({ path: файлСнимка });
  console.log('  снимок сохранён: tests/снимки/нарды-подсветка-целей-390.png');

  console.log('\n=== 3. Промах по недопустимому пункту — не тихий сброс, а слово в строке состояния ===');
  const промах = await страница.evaluate((цветСвоих) => {
    const все = Array.from(document.querySelectorAll('.пункт[data-пункт]'));
    const источник = document.querySelector('.пункт--выбран');
    // Недопустимый пункт для промаха: не подсвечен, не содержит ходкую
    // шашку, и точно НЕ своя шашка (иначе клик — это перекладывание
    // руки, а не промах: правила его примут без единого слова).
    const цель = все.find((п) => {
      if (п === источник) return false;
      if (п.classList.contains('пункт--можно')) return false;
      if (п.querySelector('.шашка--можно-взять')) return false;
      const верхняя = п.querySelector('.шашка');
      if (!верхняя) return true;
      const цветВерхней = верхняя.classList.contains('шашка--белая') ? 'белая' : 'чёрная';
      return цветВерхней !== цветСвоих;
    });
    return цель ? цель.dataset.пункт : null;
  }, источникИнфо.цвет);
  проверить(Boolean(промах), 'на доске нашёлся заведомо недопустимый пункт для промаха');

  if (промах) {
    await страница.evaluate((номер) => {
      document.querySelector('.пункт[data-пункт="' + номер + '"]').dispatchEvent(
        new MouseEvent('click', { bubbles: true }));
    }, промах);
    await страница.waitForTimeout(250);

    const послеПромаха = await страница.evaluate(() => {
      const узел = document.getElementById('подсказка-хода');
      return {
        подсказка: (узел.textContent || '').trim(),
        // Строка подсказки почти всегда чем-то занята («Осталось кубиков:
        // N», «Выберите, куда пойти») — «просто непустая» ничего не
        // доказывает, тихий сброс тоже оставляет там нейтральный текст.
        // Настоящее объяснение отказа обновитьСтроки() отмечает ОТДЕЛЬНЫМ
        // классом (js/нарды-экран.js: «подсказка-хода--объяснение») — это
        // и есть точный признак, что слово сказано именно про промах.
        объяснениеЕсть: узел.classList.contains('подсказка-хода--объяснение')
      };
    });
    console.log('  подсказка после промаха: ' + JSON.stringify(послеПромаха.подсказка) +
      ' (класс «объяснение»: ' + послеПромаха.объяснениеЕсть + ')');
    проверить(послеПромаха.объяснениеЕсть,
      'после промаха показано именно ОБЪЯСНЕНИЕ отказа, а не нейтральная строка (получили текст: «' +
      послеПромаха.подсказка + '»)');
    проверить(Boolean(послеПромаха.подсказка),
      'строка состояния после промаха НЕ пустая (получили: «' + послеПромаха.подсказка + '»)');

    const выборСброшен = await страница.evaluate(() => !document.querySelector('.пункт--выбран'));
    проверить(выборСброшен, 'выбор шашки сброшен после промаха (класс «пункт--выбран» снят)');
  }

  проверить(ошибки.length === 0, отчётПоОшибкам(ошибки, 'красных ошибок в консоли нет'));

  await окно.close();
  await браузер.close();
  раздача.close();
  if (испорченныйЭкран) {
    try { fs.unlinkSync(испорченныйЭкран.копия); } catch (е) { /* уже нет — и ладно */ }
    try { fs.rmdirSync(испорченныйЭкран.папка); } catch (е) { /* уже нет — и ладно */ }
  }
  if (испорченныйВид) {
    try { fs.unlinkSync(испорченныйВид.копия); } catch (е) { /* уже нет — и ладно */ }
    try { fs.rmdirSync(испорченныйВид.папка); } catch (е) { /* уже нет — и ладно */ }
  }
  console.log('\nИтого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
  process.exit(провалов === 0 ? 0 : 1);
})().catch((ошибка) => { console.error('проверка сломалась:', ошибка); process.exit(2); });
