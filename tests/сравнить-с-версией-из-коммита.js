const path = require('path');
const fs = require('fs');
const os = require('os');
const { execSync } = require('child_process');

const ПАРТИЙ = Number(process.argv[2]) || 200;
const КОРЕНЬ = path.join(__dirname, '..');

/* Достаём старую игру из последнего коммита. Файл кладём во временную
   папку системы: в проекте после проверки не должно остаться ничего. */
const временнаяПапка = fs.mkdtempSync(path.join(os.tmpdir(), 'дурак-сверка-'));
const путьСтарой = path.join(временнаяПапка, 'игра-из-коммита.js');
try {
  const текст = execSync('git show HEAD:js/game.js', { cwd: КОРЕНЬ, maxBuffer: 64 * 1024 * 1024 });
  fs.writeFileSync(путьСтарой, текст);
} catch (е) {
  console.error('Не удалось достать игру из коммита: ' + (е && е.message));
  process.exit(2);
}

/* СРАВНИВАТЬ ЕСТЬ ЧТО ТОЛЬКО ТОГДА, КОГДА ПРАВКА ЕЩЁ НЕ В КОММИТЕ.
   Этот стенд сверяет рабочее дерево с последним коммитом, и зовут его
   ПЕРЕД коммитом — пока правка лежит непринятой. После коммита обе
   версии становятся одной и той же, «разница обязана быть» превращается
   в неправду, и стенд краснел на ровном месте: именно так он и провалил
   общий прогон 10 сентября. Молча зеленеть тут тоже нельзя — скажем
   вслух, что сравнивать было нечего. */
const текстНынешней = fs.readFileSync(path.join(КОРЕНЬ, 'js', 'game.js'), 'utf8');
const текстИзКоммита = fs.readFileSync(путьСтарой, 'utf8');
if (текстНынешней === текстИзКоммита) {
  console.log('Правил в рабочем дереве не меняли: js/game.js в точности такой же, ' +
    'как в последнем коммите.');
  console.log('Сравнивать нечего — стенд нужен ДО коммита, пока правка ещё не принята.');
  try { fs.unlinkSync(путьСтарой); fs.rmdirSync(временнаяПапка); } catch (е) { /* не страшно */ }
  process.exit(0);
}

const нынешняя = require(path.join(КОРЕНЬ, 'js', 'game.js'));
const изКоммита = require(путьСтарой);
const генератор = require(path.join(__dirname, 'общий-генератор.js'));

/** Слепок состояния — всё, что видно снаружи. */
function слепок(игра, п) {
  const руки = п.игроки.map(function (и) { return и + ':' + п.руки[и].length; }).join(' ');
  const стол = п.стол.map(function (пара) {
    return пара.атака.имя + пара.атака.масть + '/' + (пара.защита ? пара.защита.имя + пара.защита.масть : '-');
  }).join(' ');
  return [игра.фаза(п), 'ходит=' + игра.ктоХодит(п), 'атакует=' + п.атакует,
    'отбивается=' + игра.защищается(п), 'стол=[' + стол + ']', 'руки=' + руки,
    'колода=' + п.колода.length, 'отбой=' + п.отбой.length,
    'выбыли=' + (п.выбывшие || []).join(',')].join(' | ');
}

/**
 * Сыграть партию одной из версий. Ходы выбираются по своему потоку
 * случайности с общим зерном — значит обе версии в одинаковых положениях
 * сделают одинаковый выбор, и любое расхождение будет виной правил,
 * а не разной случайности.
 */
function сыграть(игра, настройки, зерно) {
  генератор.захватитьСлучайность();
  генератор.поставитьЗерно(зерно);
  const п = игра.создатьПартию(настройки);
  const бросок = генератор.создатьПоток(зерно ^ 0x2f1b);
  const журнал = [слепок(игра, п)];

  let шагов = 0;
  while (!п.завершена && шагов++ < 700) {
    const кто = игра.ктоХодит(п);
    if (!кто) break;
    const фаза = игра.фаза(п);
    const рука = п.руки[кто] || [];

    if (фаза === 'защита') {
      let сходил = false;
      if (п.переводной && бросок() < 0.35) {
        for (let i = 0; i < рука.length; i++) {
          if (игра.можноПеревести(п, рука[i]) && игра.перевести(п, i)) { сходил = true; break; }
        }
      }
      if (!сходил) {
        const варианты = [];
        п.стол.forEach(function (пара, iП) {
          if (пара.защита) return;
          рука.forEach(function (к, iК) {
            if (игра.бьёт(к, пара.атака, п.козырь)) варианты.push([iП, iК]);
          });
        });
        if (варианты.length === 0 || бросок() < 0.2) игра.объявитьБеру(п);
        else {
          const в = варианты[Math.floor(бросок() * варианты.length)];
          игра.отбить(п, в[0], в[1]);
        }
      }
    } else {
      const годные = [];
      for (let i = 0; i < рука.length; i++) if (игра.можноПоложить(п, рука[i])) годные.push(i);
      if (годные.length === 0 || (фаза !== 'атака' && бросок() < 0.35)) игра.пас(п, кто);
      else игра.положитьВАтаку(п, кто, годные[Math.floor(бросок() * годные.length)]);
    }
    журнал.push(слепок(игра, п));
  }
  журнал.push('КОНЕЦ: ' + (п.результат || 'не доиграна'));
  return журнал;
}

/* Столы без пар обязаны совпасть ход в ход. А парные — наоборот: ради них
   правку и делали, и если они СОВПАДУТ, значит проверка ничего не видит
   и верить её «всё совпало» нельзя. Поэтому парный стол здесь стоит
   самопроверкой: помечен «ждёмРазницу». */
const раскладки = [
  { имя: 'вдвоём',              набор: 'обычный' },
  { имя: 'трое',                набор: { игроков: 3 } },
  { имя: 'четверо',             набор: { игроков: 4 } },
  { имя: 'пятеро',              набор: { игроков: 5 } },
  { имя: 'шестеро',             набор: { игроков: 6 } },
  { имя: 'четверо, переводной', набор: { игроков: 4, переводной: true } },
  { имя: 'шестеро, переводной', набор: { игроков: 6, переводной: true } },
  { имя: 'четверо, ПАРАМИ (тут разница обязана быть)',
    набор: { игроков: 4, парами: true }, ждёмРазницу: true }
];

console.log('=== Та же ли это игра: нынешние правила против версии из коммита ===');
console.log('партий на раскладку: ' + ПАРТИЙ);

let расхождений = 0;
let сверено = 0;
let проверкаСлепа = false;
const примеры = [];

for (const раскладка of раскладки) {
  let одинаковых = 0;
  for (let н = 1; н <= ПАРТИЙ; н++) {
    const зерно = (н * 6151 + 17) | 0;
    const было = сыграть(изКоммита, раскладка.набор, зерно);
    const стало = сыграть(нынешняя, раскладка.набор, зерно);
    сверено++;
    if (было.length === стало.length && было.every(function (с, i) { return с === стало[i]; })) {
      одинаковых++;
      continue;
    }
    if (раскладка.ждёмРазницу) continue;      // тут разница и должна быть
    расхождений++;
    if (примеры.length < 5) {
      let где = 0;
      while (где < Math.min(было.length, стало.length) && было[где] === стало[где]) где++;
      примеры.push(раскладка.имя + ', партия №' + н + ', разошлись на ходу ' + где +
        '\n      было:  ' + (было[где] || '(ход не сделан)') +
        '\n      стало: ' + (стало[где] || '(ход не сделан)'));
    }
  }
  const разошлись = ПАРТИЙ - одинаковых;
  console.log('  ' + раскладка.имя + ': совпало ' + одинаковых + ' из ' + ПАРТИЙ +
    (раскладка.ждёмРазницу ? ' (разошлись ' + разошлись + ' — так и должно быть)' : ''));
  if (раскладка.ждёмРазницу && разошлись === 0) {
    проверкаСлепа = true;
    console.log('    ВНИМАНИЕ: парный стол не изменился вовсе. Либо правку не применили,');
    console.log('    либо эта проверка ничего не видит — и её «всё совпало» ничего не значит.');
  }
}

console.log('\nсверено партий: ' + сверено + ', разошлись там, где не должны: ' + расхождений);
if (расхождений) {
  console.log('РАСХОЖДЕНИЯ (первые ' + примеры.length + '):');
  примеры.forEach(function (п) { console.log('  - ' + п); });
}

// За собой прибираем: временная копия старой игры нам больше не нужна.
try { fs.unlinkSync(путьСтарой); fs.rmdirSync(временнаяПапка); } catch (е) { /* не страшно */ }

if (расхождений || проверкаСлепа) process.exit(1);
console.log('=== Итог: на столах без пар обе версии играют ход в ход одинаково,');
console.log('    а парный стол изменился — значит проверка и вправду смотрит ===');
