const ПРОВЕРКИ = [['п1', п1], ['п2', п2], ['п3', п3], ['п4', п4]];

function прогнать(файлы) {
  const красное = [];
  for (const [имя, проверка] of ПРОВЕРКИ) {
    try { проверка(файлы); } catch (е) { красное.push(/^п[0-9]:/.test(е.message) ? е.message : имя + ': сбой проверки — ' + е.message); }
  }
  return красное;
}

function копияСПорчей(порча) {
  fs.mkdirSync(КОПИИ, { recursive: true });
  const копии = {};
  for (const [ключ, откуда] of Object.entries(НАСТОЯЩИЕ)) {
    копии[ключ] = path.join(КОПИИ, 'копия' + порча.номер + '-' + path.basename(откуда));
    fs.copyFileSync(откуда, копии[ключ]);
  }
  const текст = fs.readFileSync(копии[порча.файл], 'utf8').split('\r\n').join('\n');
  if (!текст.includes(порча.было)) return null;
  fs.writeFileSync(копии[порча.файл], текст.replace(порча.было, порча.стало));
  return копии;
}

function порчаКраснеет(порча) {
  const файлы = копияСПорчей(порча);
  if (!файлы) { console.log('  порча ' + порча.номер + ': строка для порчи не найдена — ' + порча.зачем); process.exitCode = 2; return false; }
  const красное = прогнать(файлы);
  console.log('  порча ' + порча.номер + ' (' + порча.зачем + '): ' + (красное.length ? 'красная, как и нужно — ' + красное[0] : 'ЗЕЛЁНАЯ — проверка не поймала порчу'));
  return красное.some(с => с.startsWith(порча.пункт + ':'));
}

