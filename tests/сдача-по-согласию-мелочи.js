/* ---------- п2: класс под вуалью на поддельной странице ---------- */
function новыйЭлемент(реестр) {
  const классы = new Set(), слушатели = {}, атрибуты = {};
  let идентификатор = '', текст = '';
  const эл = {
    children: [], parentNode: null, disabled: false, offsetParent: {},
    classList: {
      add: к => классы.add(к), remove: к => классы.delete(к), contains: к => классы.has(к),
      toggle: (к, надо) => { if (надо === undefined ? !классы.has(к) : Boolean(надо)) классы.add(к); else классы.delete(к); }
    },
    setAttribute: (к, з) => { атрибуты[к] = String(з); }, getAttribute: к => (к in атрибуты ? атрибуты[к] : null),
    removeAttribute: к => { delete атрибуты[к]; },
    addEventListener: (тип, fn) => { (слушатели[тип] = слушатели[тип] || []).push(fn); },
    click: () => { (слушатели.click || []).forEach(fn => fn({})); },
    appendChild: р => эл.insertBefore(р, null),
    insertBefore(р, опора) {
      if (р.parentNode) р.parentNode.children.splice(р.parentNode.children.indexOf(р), 1);
      const и = опора ? эл.children.indexOf(опора) : -1;
      if (и === -1) эл.children.push(р); else эл.children.splice(и, 0, р);
      р.parentNode = эл;
      return р;
    },
    contains: у => { for (let т = у; т; т = т.parentNode) if (т === эл) return true; return false; },
    querySelector: sel => найтиПоКлассу(эл, sel.replace(/^\./, '').split(':')[0]),
    querySelectorAll: () => [],
    focus() {}
  };
  Object.defineProperty(эл, 'id', { get: () => идентификатор, set: з => { идентификатор = з; реестр.set(з, эл); } });
  Object.defineProperty(эл, 'nextSibling', { get: () => { const с = эл.parentNode && эл.parentNode.children; return с ? с[с.indexOf(эл) + 1] || null : null; } });
  Object.defineProperty(эл, 'textContent', { get: () => текст, set: з => { эл.children.length = 0; текст = String(з); } });
  return эл;
}
function найтиПоКлассу(корень, класс) {
  for (const р of корень.children) {
    if (р.classList.contains(класс)) return р;
    const в = найтиПоКлассу(р, класс);
    if (в) return в;
  }
  return null;
}

