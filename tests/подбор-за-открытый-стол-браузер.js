async function ariaCheckedПодбора(страница) {
  const у = страница.locator('#комната-подбор');
  if ((await у.count()) === 0) return null;
  return у.getAttribute('aria-checked');
}

async function дождатьсяAriaChecked(страница, значение, таймаутМс) {
  try {
    await страница.waitForFunction(function (знач) {
      const у = document.getElementById('комната-подбор');
      return Boolean(у) && у.getAttribute('aria-checked') === знач;
    }, значение, { timeout: таймаутМс || 8000 });
    return true;
  } catch (сбой) {
    return false;
  }
}

/** Узел не найден — честный провал (Boolean(...) === false), а не тихий пропуск. */
async function видЭкранаПодбора(страница) {
  return страница.evaluate(function () {
    const экран = document.getElementById('экран-подбор-соперника');
    if (!экран) return { экранВиден: false, непустой: false, ожиданиеТекст: '' };
    const ожидание = document.getElementById('подбор-ожидание');
    return {
      экранВиден: экран.classList.contains('экран--виден'),
      непустой: экран.children.length > 0,
      ожиданиеТекст: ожидание ? ожидание.textContent.trim() : ''
    };
  });
}

/* =======================================================================
   Сценарий 1. Хозяин создаёт открытый стол, переключает подбор,
   гость находит его именно этот стол через «Найти игру».
   ======================================================================= */
async function хозяинИГостьЗаОднимСтолом(браузер, папкаСнимков) {
  console.log('\n=== Хозяин открывает стол, гость находит его через «Найти игру» ===');
  const хозяин = await новаяСтраница(браузер, { подпись: initDataИгрока(940101, 'Хозяин') });
  await хозяин.страница.goto(АДРЕС_ФАЙЛОВ + 'index.html?сервер=' + encodeURIComponent(АДРЕС_КОМНАТ));

  const код = await путьХозяина(хозяин.страница);
  проверить(/^[A-Z0-9]{4,}$/.test(код), 'у хозяина показан код комнаты: «' + код + '»');

  const включёнСразу = await ariaCheckedПодбора(хозяин.страница);
  проверить(включёнСразу === 'true',
    'стол, созданный мастером «Создать игру», сразу открыт для подбора (aria-checked=«' + включёнСразу + '»)');

  if (папкаСнимков) {
    await хозяин.страница.screenshot({ path: path.join(папкаСнимков, 'подбор-хозяин-1-включён-390.png') });
    сказать('снимок 1 (включён): ' + path.join(папкаСнимков, 'подбор-хозяин-1-включён-390.png'));
  }

  await нажать(хозяин.страница, хозяин.страница.locator('#комната-подбор'));
  проверить(await дождатьсяAriaChecked(хозяин.страница, 'false', 8000),
    'клик по переключателю выключил подбор (aria-checked стал «false»)');

  if (папкаСнимков) {
    await хозяин.страница.screenshot({ path: path.join(папкаСнимков, 'подбор-хозяин-2-выключён-390.png') });
    сказать('снимок 2 (выключен): ' + path.join(папкаСнимков, 'подбор-хозяин-2-выключён-390.png'));
  }

  await нажать(хозяин.страница, хозяин.страница.locator('#комната-подбор'));
  проверить(await дождатьсяAriaChecked(хозяин.страница, 'true', 8000),
    'повторный клик снова включил подбор (aria-checked стал «true»)');

  const гость = await новаяСтраница(браузер, { подпись: initDataИгрока(940102, 'Гость') });
  await гость.страница.goto(АДРЕС_ФАЙЛОВ + 'index.html?сервер=' + encodeURIComponent(АДРЕС_КОМНАТ));
  await путьГостяДоНайтиИгру(гость.страница);

  let дошёлДоКомнаты = true;
  try {
    await дождаться(гость.страница, 'экран-комнаты', 12000);
  } catch (сбой) {
    дошёлДоКомнаты = false;
  }
  проверить(дошёлДоКомнаты, 'гость через «Найти игру» дошёл до экрана комнаты (не завис в ожидании)');

  let кодУГостя = '';
  if (дошёлДоКомнаты) {
    await гость.страница.waitForSelector('#комната:not(.скрыт)', { timeout: 8000 }).catch(function () {});
    кодУГостя = (await гость.страница.locator('#код-комнаты').textContent().catch(function () { return ''; }) || '').trim();
  }
  проверить(Boolean(кодУГостя) && кодУГостя === код,
    'гость попал именно за стол хозяина: у хозяина код «' + код + '», у гостя «' + кодУГостя + '»');

  const дождалисьГостя = await хозяин.страница.waitForFunction(function (имя) {
    const имена = Array.from(document.querySelectorAll('.рассадка__место .рассадка__имя'))
      .map(function (у) { return у.textContent || ''; });
    return имена.some(function (т) { return т.indexOf(имя) !== -1; });
  }, 'Гость', { timeout: 10000 }).then(function () { return true; }).catch(function () { return false; });
  проверить(дождалисьГостя, 'у хозяина в рассадке появилось имя гостя «Гость»');

  const кнопкаНачатьЗаблокирована = await хозяин.страница.locator('#комната-начать').isDisabled().catch(function () { return true; });
  проверить(!кнопкаНачатьЗаблокирована, 'у хозяина кнопка «Начать» стала доступна (disabled снят)');

  if (папкаСнимков) {
    await хозяин.страница.screenshot({ path: path.join(папкаСнимков, 'подбор-хозяин-3-гость-подсел-390.png') });
    сказать('снимок 3 (гость подсел): ' + path.join(папкаСнимков, 'подбор-хозяин-3-гость-подсел-390.png'));
  }

  проверить(хозяин.ошибки.length === 0, 'у хозяина красных ошибок в консоли нет' +
    (хозяин.ошибки.length ? ' — ' + хозяин.ошибки.join(' | ') : ''));
  проверить(гость.ошибки.length === 0, 'у гостя красных ошибок в консоли нет' +
    (гость.ошибки.length ? ' — ' + гость.ошибки.join(' | ') : ''));

  await хозяин.контекст.close();
  await гость.контекст.close();
}

