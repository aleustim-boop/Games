'use strict';

/* =====================================================================
   Напарник для проверок в браузере: садится за стол вторым игроком,
   играет сам и всегда соглашается на реванш.

   Зачем он нужен. Некоторые вещи проверяются только в НАСТОЯЩЕЙ игре
   с другом: например, кнопка «Ещё партию» в сетевой партии уходит совсем
   не той дорогой, что в игре с ботом. Для этого нужен живой второй игрок
   за столом, а браузер у проверяющего один. Вот этот напарник его и
   заменяет: для сервера он такой же игрок, как человек с телефона, —
   со своим пропуском и своим длинным опросом.

   Как запускать (сервер комнат уже поднят):

       node tests/напарник-для-браузера.js 8825 создать
           создаёт комнату на двоих и печатает код — код набирают в браузере
           («Играть с другом» → «Войти по коду»);

       node tests/напарник-для-браузера.js 8825 войти AB12
           входит в комнату, которую создали в браузере.

   Дальше напарник живёт сам: ходит, когда его очередь, и жмёт «Сыграть
   ещё» всякий раз, как партия кончилась. Останавливать — Ctrl+C.

   Играет он нарочно просто и предсказуемо: кроет самой мелкой подходящей
   картой, ходит с мелочи, козыри бережёт. Никаких хитростей: его дело —
   не выиграть, а не дать столу простаивать, пока проверяющий занят
   своими замерами.
   ===================================================================== */

const http = require('http');

const ПОРТ = Number(process.argv[2]) || 8825;
const ЧТО_ДЕЛАТЬ = (process.argv[3] || 'создать').toLowerCase();
const КОД_КОМНАТЫ = (process.argv[4] || '').toUpperCase();

/* Через сколько секунд напарник сам встанет из-за стола и уйдёт по-человечески
   (запросом «выйти»), а не просто пропадёт со связи. Нужно, чтобы проверять
   случай «друг вышел из партии»: он выглядит для оставшегося совсем не так,
   как обрыв связи. Не сказали — не уходит вовсе, играет, пока не остановят.

       node tests/напарник-для-браузера.js 8825 создать - уйти-через 25 */
const УЙТИ_ЧЕРЕЗ = (function () {
  const где = process.argv.indexOf('уйти-через');
  if (где === -1) return 0;
  const секунд = Number(process.argv[где + 1]);
  return Number.isFinite(секунд) && секунд > 0 ? Math.round(секунд * 1000) : 0;
})();
const ХОЗЯИН = '127.0.0.1';
/* Имя, под которым напарник садится за стол. По умолчанию короткое,
   но его можно задать своим — длинные имена нужны, чтобы проверить самые
   длинные подсказки («Александра-Мария возвращается за стол — …»):

       node tests/напарник-для-браузера.js 8790 войти AB12 имя Александра-Мария */
const МОЁ_ИМЯ = (function () {
  const где = process.argv.indexOf('имя');
  const своё = где === -1 ? '' : String(process.argv[где + 1] || '').trim();
  return своё || 'Напарник';
})();

/* Длинный опрос сервер держит до 25 секунд (или сколько ему сказали
   при запуске). Ждём с запасом, иначе свой же обрыв примем за молчание. */
const ЖДЁМ_ДОЛГО = 40000;
const ЖДЁМ_КОРОТКО = 15000;

function спросить(путь, тело, сколькоЖдать) {
  return new Promise((готово, беда) => {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, (ответ) => {
      let текст = '';
      ответ.setEncoding('utf8');
      ответ.on('data', (к) => { текст += к; });
      ответ.on('end', () => {
        let р = null;
        try { р = JSON.parse(текст); } catch (сбой) { р = { сырое: текст }; }
        готово({ код: ответ.statusCode, тело: р });
      });
    });
    запрос.setTimeout(сколькоЖдать || ЖДЁМ_КОРОТКО,
      () => запрос.destroy(new Error('сервер молчит дольше положенного')));
    запрос.on('error', беда);
    запрос.end(данные);
  });
}

const пауза = (мс) => new Promise((r) => setTimeout(r, мс));

function бьёт(чем, что, козырь) {
  if (чем.масть === что.масть) return чем.вес > что.вес;
  return чем.масть === козырь && что.масть !== козырь;
}

/** Самая мелкая из годных карт; козырь берём только когда другого нет. */
function мелкая(рука, номера, козырь) {
  const некозырные = номера.filter((i) => рука[i].масть !== козырь);
  const из = некозырные.length ? некозырные : номера;
  return из.reduce((лучший, i) => (рука[i].вес < рука[лучший].вес ? i : лучший), из[0]);
}

/** Что делать при своём ходе. Возвращает намерение или null. */
function решить(вид) {
  const рука = вид.мояРука || [];
  const стол = вид.стол || [];
  const козырь = вид.козырь;

  /* Отбиваюсь ли я. Осторожно: поле «яОтбиваюсь» сервер шлёт ТОЛЬКО за столом
     компанией (трое и больше). В обычной партии вдвоём его нет вовсе, и раньше
     напарник об этом не знал: ветка отбоя не срабатывала ни разу, он на каждую
     атаку говорил «Беру» и добирал колоду до конца. Партии от этого выглядели
     дико («у друга 36 карт»), а проверка сетевой игры вдвоём была пустой.
     Вдвоём считаем так же, как это делает сама игра: ходит не тот, кто атакует,
     значит, отбивается. */
  const яОтбиваюсь = вид.яОтбиваюсь !== undefined
    ? вид.яОтбиваюсь
    : Boolean(вид.яХожу && !вид.яАтакую);

  if (яОтбиваюсь && !вид.берут) {
    const номерПары = стол.findIndex((п) => !п.защита);
    if (номерПары < 0) return null;
    const атака = стол[номерПары].атака;
    const годные = [];
    рука.forEach((к, i) => { if (атака && бьёт(к, атака, козырь)) годные.push(i); });
    if (годные.length) {
      return { действие: 'отбить', пара: номерПары, карта: мелкая(рука, годные, козырь) };
    }
    return { действие: 'беру' };
  }

  if (вид.яХожу && !яОтбиваюсь) {
    if (!рука.length) return стол.length ? { действие: 'бито' } : null;
    if (!стол.length) {
      const все = рука.map((к, i) => i);
      return { действие: 'ходить', карта: мелкая(рука, все, козырь) };
    }
    const достоинства = new Set();
    стол.forEach((п) => {
      if (п.атака) достоинства.add(п.атака.имя);
      if (п.защита) достоинства.add(п.защита.имя);
    });
    const годные = [];
    рука.forEach((к, i) => { if (достоинства.has(к.имя) && к.масть !== козырь) годные.push(i); });
    if (годные.length) return { действие: 'ходить', карта: мелкая(рука, годные, козырь) };
    return { действие: 'бито' };
  }
  return null;
}

/* ---------------------------------------------------------------------
   Жизнь за столом
   --------------------------------------------------------------------- */

async function главная() {
  let код = КОД_КОМНАТЫ;
  let пропуск = null;
  let вид = null;

  if (ЧТО_ДЕЛАТЬ === 'создать') {
    /* Создаём комнату БЕЗ настроек — это та самая «старая комната на двоих»,
       где карты раздаются сами, как только вошёл друг. Кнопки «Начать» там
       нет вовсе, а напарник её и не нажал бы: он умеет только играть.
       Стоит послать хоть одну настройку (например «мест: 2») — и комната
       станет комнатой-компанией с прихожей, в которой вошедший будет ждать
       вечно. */
    const создано = await спросить('/создать', { имя: МОЁ_ИМЯ });
    if (создано.код !== 200 || !создано.тело.код) {
      throw new Error('не дали создать комнату: ' + JSON.stringify(создано.тело));
    }
    код = создано.тело.код;
    пропуск = создано.тело.пропуск;
    вид = создано.тело.состояние;
    console.log('');
    console.log('   КОД КОМНАТЫ: ' + код);
    console.log('   Наберите его в игре: «Играть с другом» → «Войти по коду».');
    console.log('');
  } else {
    if (!код) throw new Error('не сказали код комнаты');
    const вход = await спросить('/войти', { код: код, имя: МОЁ_ИМЯ });
    if (вход.код !== 200 || !вход.тело.пропуск) {
      throw new Error('не пустили в комнату: ' + JSON.stringify(вход.тело));
    }
    пропуск = вход.тело.пропуск;
    вид = вход.тело.состояние;
    console.log('Вошёл в комнату ' + код + '. Играю за второго и всегда соглашаюсь на реванш.');
  }

  let сыгранных = -1;
  let звалиНа = -1;
  let последнийХод = -1;

  /* Уход по-человечески: сервер узнаёт о нём сразу, и оставшийся видит
     «друг вышел», а не «связь потеряна». */
  if (УЙТИ_ЧЕРЕЗ > 0) {
    setTimeout(async function () {
      await спросить('/выйти', { код, пропуск }).catch(() => {});
      console.log('Встал из-за стола и вышел из комнаты (прошло ' +
        Math.round(УЙТИ_ЧЕРЕЗ / 1000) + ' с).');
      process.exit(0);
    }, УЙТИ_ЧЕРЕЗ);
  }

  // Слушаем новости длинным опросом и ходим, когда наша очередь.
  let версия = вид ? вид.версия : 0;
  for (;;) {
    if (вид) {
      // Партия кончилась — сразу соглашаемся играть ещё.
      if (вид.завершена) {
        const какая = вид.сыграноПартий || 0;
        if (звалиНа !== какая) {
          звалиНа = какая;
          await спросить('/ход', { код, пропуск, действие: 'ещё' }).catch(() => {});
          console.log('Партия кончилась — согласился на реванш.');
        }
      } else if (вид.яХожу && вид.номерСобытия !== последнийХод) {
        последнийХод = вид.номерСобытия;
        const намерение = решить(вид);
        const попытки = [];
        if (намерение) попытки.push(намерение);
        попытки.push({ действие: 'бито' }, { действие: 'беру' });
        for (const шаг of попытки) {
          const о = await спросить('/ход', Object.assign({ код, пропуск }, шаг)).catch(() => null);
          if (о && о.тело && о.тело.состояние) вид = о.тело.состояние;
          if (о && о.тело && о.тело.принято) break;
        }
        if (вид) версия = вид.версия;
        continue;
      }
      if (вид.сыграноПартий !== сыгранных) {
        сыгранных = вид.сыграноПартий;
        if (сыгранных > 0) console.log('Партий сыграно: ' + сыгранных);
      }
    }

    let ответ = null;
    try {
      ответ = await спросить('/что-нового', { код, пропуск, версия }, ЖДЁМ_ДОЛГО);
    } catch (сбой) {
      await пауза(500);
      continue;
    }
    if (ответ.тело && ответ.тело.комнатыНет) {
      console.log('Комнату убрали — напарник уходит.');
      return;
    }
    if (ответ.тело && ответ.тело.состояние) {
      вид = ответ.тело.состояние;
      версия = вид.версия;
    }
  }
}

главная().catch((сбой) => {
  console.error('Сорвалось: ' + сбой.message);
  process.exitCode = 1;
});
