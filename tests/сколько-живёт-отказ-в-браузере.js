'use strict';

/* =====================================================================
   Сколько времени ответ на нажатие ВПРАВДУ виден на экране.

   ЭТО НЕ АВТОПРОГОН ДЛЯ NODE. Файл целиком вставляется в консоль браузера,
   когда игра уже открыта (http://…/index.html). Node его запускать не надо:
   здесь меряется живой экран.

   ЗАЧЕМ ОН НУЖЕН. Живой новичок сказал про игру: «нажимаю на карту, когда
   соперник думает, — и ничего не происходит, я решил, что игра подвисла».
   Это уже проверяли и выяснили: игра отвечает всегда. Ответов у неё два,
   и оба короткие по времени:

     • слова в строке подсказки — их держат ПОКАЗ_СЛОВ_ОТКАЗА;
     • вздрагивание самой карты — его держат ПОКАЗ_ОТКАЗА.

   Но «сколько держат» и «сколько видно» — это разные вещи. Ход соперника
   стирает оба ответа разом: он ставит в строку свой рассказ, а руку
   перерисовывает заново — вместе с пометкой на карте. И если человек ткнул
   за миг до чужого хода, ответ проживёт не свои две секунды, а десятую
   долю секунды. Со стороны это неотличимо от «игра не ответила».

   Этот замер и считает, сколько ответ прожил НА САМОМ ДЕЛЕ. Числа из игры
   он не переписывает: сколько положено держать, спрашивается у самой игры
   («держатПоложено»), а сколько вышло — меряется по экрану.

   ЧТО ЗАПУСКАТЬ (после вставки файла звать по одному):

     жизньОтказа.наЧужомХоду(30)
         Тридцать раз ткнуть в свою карту, пока ходит соперник, каждый раз
         выждав случайное время после его прошлого хода — как это делает
         нетерпеливый человек. Печатает, сколько прожили слова и вздрагивание.

     жизньОтказа.наСвоёмХоду(12)
         То же самое, но на своём ходу: тычем в карту, которой сейчас нельзя.
         Здесь соперник не ходит и стирать ответ некому — по этим числам
         видно, сколько ответ живёт, когда ему не мешают.

     жизньОтказа.всё()
         Оба замера подряд и короткий вывод.

   Замеры сами играют законными ходами, чтобы партия не вставала, и сами
   начинают новую, когда прежняя доиграна.
   ===================================================================== */

(function () {
  'use strict';

  const пауза = (мс) => new Promise((r) => setTimeout(r, мс));
  const строка = () => {
    const узел = document.getElementById('подсказка-текст');
    return узел ? узел.textContent : '';
  };
  const естьВздрог = () =>
    document.querySelectorAll('#карты-человека .карта--отказ').length > 0;

  /** Идёт ли партия прямо сейчас. */
  const партияИдёт = () => Boolean(партия) && !партия.завершена;

  /**
   * Один законный ход за человека — чтобы стол двигался, пока мы меряем.
   * Зовём те же функции, что и кнопки на экране.
   */
  function сходитьЗаконно() {
    if (!партияИдёт() || !сейчасМойХод()) return;
    const текущая = фаза(партия);
    if (текущая === 'защита') {
      for (let п = 0; п < партия.стол.length; п++) {
        if (партия.стол[п].защита) continue;
        for (let к = 0; к < партия.руки.человек.length; к++) {
          if (бьёт(партия.руки.человек[к], партия.стол[п].атака, партия.козырь)) {
            отбитьсяКартой(п, к);
            return;
          }
        }
      }
      нажатьБеру();
      return;
    }
    for (let к = 0; к < партия.руки.человек.length; к++) {
      if (можноПоложить(партия, партия.руки.человек[к])) { сходитьКартой(к); return; }
    }
    if (мнеМожноЗакончитьПодход(текущая)) нажатьБито();
  }

  /** Начать партию, если прежняя доиграна. */
  async function держатьПартиюЖивой() {
    if (партияИдёт()) return;
    начатьПартию();
    await пауза(500);
  }

  /**
   * Ткнуть и дождаться, пока ответ пропадёт с экрана. Возвращает, сколько
   * миллисекунд прожили слова и сколько — вздрагивание карты.
   * Ноль в «словаЖили» значит, что нажатие вообще не дало отказа
   * (попали в законный ход) — такие пробы в счёт не идут.
   */
  async function ткнутьИЗасечь(номерКарты) {
    /* Окно глухоты после кнопки снимаем: оно бережёт живой палец от «хвоста»
       касания, а нам мешает — проба просто пропала бы молча. Мы меряем
       длину ответа, а не глухоту (для неё есть свой замер). */
    рукаГлухаДо = 0;
    прошлыеСловаОтказа = '';
    const было = строка();
    тапПоКартеЧеловека(номерКарты);
    const отказ = строка();
    if (отказ === было) return null;    // нажатие оказалось законным ходом

    const начало = Date.now();
    await пауза(30);                    // пометка на карте вешается через кадр
    let словаЖивы = true;
    let вздрогЖив = естьВздрог();
    let словаДо = 0;
    let вздрогДо = вздрогЖив ? 0 : -1;  // −1: вздрагивания не было вовсе
    while (Date.now() - начало < 4000 && (словаЖивы || вздрогЖив)) {
      await пауза(20);
      if (словаЖивы && строка() !== отказ) { словаЖивы = false; словаДо = Date.now() - начало; }
      if (вздрогЖив && !естьВздрог()) { вздрогЖив = false; вздрогДо = Date.now() - начало; }
    }
    return {
      словаЖили: словаЖивы ? 4000 : словаДо,
      вздрогЖил: вздрогЖив ? 4000 : вздрогДо,
      отказ: отказ
    };
  }

  /** Простая сводка по числам: самое малое, середина, самое большое. */
  function сводка(числа) {
    const с = числа.slice().sort((а, б) => а - б);
    return {
      проб: с.length,
      самыйКороткий: с[0],
      середина: с[Math.floor(с.length / 2)],
      самыйДлинный: с[с.length - 1],
      корочеПолсекунды: с.filter((м) => м < 500).length,
      корочеСекунды: с.filter((м) => м < 1000).length
    };
  }

  /** Сколько игра СОБИРАЕТСЯ держать ответ — спрашиваем у неё самой. */
  function держатПоложено() {
    return {
      словаМс: (typeof ПОКАЗ_СЛОВ_ОТКАЗА === 'number') ? ПОКАЗ_СЛОВ_ОТКАЗА : '?',
      вздрогМс: (typeof ПОКАЗ_ОТКАЗА === 'number') ? ПОКАЗ_ОТКАЗА : '?',
      сколькоЖдётСоперникПодСообщение:
        (typeof ПАУЗА_ПОД_СОБЫТИЕ === 'number') ? ПАУЗА_ПОД_СОБЫТИЕ : '?'
    };
  }

  /**
   * Тычем в свою карту, пока ходит соперник. Перед каждым тычком выжидаем
   * случайное время — иначе все пробы придутся на один и тот же миг после
   * чужого хода, и замер покажет одно красивое число вместо разброса.
   */
  async function наЧужомХоду(сколько) {
    const надо = Number(сколько) || 30;
    const слова = [];
    const вздроги = [];
    const самыеКороткие = [];
    const крайний = Date.now() + 20000 + надо * 4000;

    while (слова.length < надо && Date.now() < крайний) {
      await пауза(60);
      await держатьПартиюЖивой();
      if (!партияИдёт() || !партия.руки.человек.length) continue;
      if (сейчасМойХод()) { рукаГлухаДо = 0; сходитьЗаконно(); continue; }

      await пауза(Math.floor(Math.random() * 1500));
      if (!партияИдёт() || сейчасМойХод() || !партия.руки.человек.length) continue;

      const проба = await ткнутьИЗасечь(0);
      if (!проба) continue;
      слова.push(проба.словаЖили);
      if (проба.вздрогЖил >= 0) вздроги.push(проба.вздрогЖил);
      самыеКороткие.push(Math.max(проба.словаЖили, проба.вздрогЖил));
    }

    const итог = {
      где: 'ходит соперник (нетерпеливый тычок в свою карту)',
      держатПоложено: держатПоложено(),
      словаНаЭкране: сводка(слова),
      вздрагиваниеКарты: вздроги.length ? сводка(вздроги) : 'вздрагиваний не было',
      любойОтветВообще: сводка(самыеКороткие)
    };
    console.log('--- Сколько живёт ответ, когда ходит соперник ---');
    console.table ? console.table(итог.словаНаЭкране) : console.log(итог.словаНаЭкране);
    console.log(итог);
    return итог;
  }

  /**
   * Тычем в карту, которой сейчас нельзя, на СВОЁМ ходу. Соперник в это
   * время ждёт нас и ответ не стирает — по этим числам видно, сколько
   * ответ живёт, когда ему никто не мешает.
   */
  async function наСвоёмХоду(сколько) {
    const надо = Number(сколько) || 12;
    const слова = [];
    const примеры = [];
    const крайний = Date.now() + 20000 + надо * 5000;

    while (слова.length < надо && Date.now() < крайний) {
      await пауза(80);
      await держатьПартиюЖивой();
      if (!партияИдёт() || !сейчасМойХод() || !партия.руки.человек.length) continue;
      рукаГлухаДо = 0;

      // Какой картой сейчас нельзя — спрашиваем у самой игры, её же
      // подсветкой: «картаСейчасХодит» решает, красить карту или гасить.
      let плохая = -1;
      for (let i = 0; i < партия.руки.человек.length; i++) {
        if (картаСейчасХодит(партия.руки.человек[i]) === false) { плохая = i; break; }
      }
      if (плохая < 0) { сходитьЗаконно(); continue; }

      const проба = await ткнутьИЗасечь(плохая);
      if (проба) {
        слова.push(проба.словаЖили);
        if (примеры.length < 3) примеры.push(проба.отказ);
      }
      сходитьЗаконно();
    }

    const итог = {
      где: 'ваш ход (тычок в карту, которой нельзя)',
      держатПоложено: держатПоложено(),
      словаНаЭкране: сводка(слова),
      примерыОтказов: примеры
    };
    console.log('--- Сколько живёт ответ на своём ходу ---');
    console.log(итог);
    return итог;
  }

  async function всё() {
    const чужой = await наЧужомХоду(30);
    const свой = await наСвоёмХоду(12);
    console.log('=== Коротко ===');
    console.log('Игра держит слова отказа ' + чужой.держатПоложено.словаМс + ' мс, ' +
      'вздрагивание — ' + чужой.держатПоложено.вздрогМс + ' мс.');
    console.log('На своём ходу так и выходит: середина ' + свой.словаНаЭкране.середина + ' мс.');
    console.log('На чужом ходу ответ стирает ход соперника: середина ' +
      чужой.словаНаЭкране.середина + ' мс, самый короткий ' +
      чужой.любойОтветВообще.самыйКороткий + ' мс; короче полсекунды — ' +
      чужой.любойОтветВообще.корочеПолсекунды + ' проб из ' + чужой.любойОтветВообще.проб + '.');
    return { чужойХод: чужой, свойХод: свой };
  }

  window.жизньОтказа = { наЧужомХоду, наСвоёмХоду, всё };
  console.log('Замер готов. Зовите: жизньОтказа.всё() — или по одному: ' +
    'жизньОтказа.наЧужомХоду(30), жизньОтказа.наСвоёмХоду(12).');
})();
