function сделатьУзел(id) {
  const классы = new Set();
  const атрибуты = {};
  const слушатели = {};
  const база = {
    id: id,
    textContent: '',
    disabled: false,
    dataset: {},
    children: [],
    classList: {
      add: function (...к) { к.forEach(function (с) { классы.add(с); }); },
      remove: function (...к) { к.forEach(function (с) { классы.delete(с); }); },
      contains: function (с) { return классы.has(с); },
      toggle: function (с, принудительно) {
        const надо = принудительно === undefined ? !классы.has(с) : Boolean(принудительно);
        if (надо) классы.add(с); else классы.delete(с);
        return надо;
      }
    },
    addEventListener: function (тип, ф) { (слушатели[тип] = слушатели[тип] || []).push(ф); },
    removeEventListener: function () {},
    запустить: function (тип, событие) { (слушатели[тип] || []).forEach(function (ф) { ф(событие || {}); }); },
    click: function () { база.запустить('click', { target: база, stopPropagation: function () {} }); },
    setAttribute: function (к, з) { атрибуты[к] = String(з); },
    getAttribute: function (к) { return к in атрибуты ? атрибуты[к] : null; },
    removeAttribute: function (к) { delete атрибуты[к]; },
    appendChild: function (х) { база.children.push(х); return х; },
    insertAdjacentElement: function (_, х) { return х; },
    insertBefore: function (х) { return х; },
    querySelector: function () { return null; },
    querySelectorAll: function () { return []; },
    closest: function () { return null; },
    contains: function () { return false; },
    remove: function () {},
    focus: function () {},
    animate: function () {},
    getBoundingClientRect: function () { return { left: 0, top: 0, width: 0, height: 0 }; },
    style: { setProperty: function () {}, removeProperty: function () {}, getPropertyValue: function () { return ''; } },
    parentNode: null,
    parentElement: null,
    firstChild: null
  };
  Object.defineProperty(база, 'className', {
    get: function () { return Array.from(классы).join(' '); },
    set: function (з) { классы.clear(); String(з).split(/\s+/).filter(Boolean).forEach(function (с) { классы.add(с); }); }
  });
  return база;
}

/** Песочница одной «открытой страницы». Память хранилища общая между страницами. */
function открытьСтраницу(хранилище, настройки) {
  const узлы = {};
  const созданные = [];
  const слушателиОкна = {};
  const очередь = [];
  let времяТаймеров = 0;
  const нетТакихУзлов = new Set(['кнопка-доиграть-с-ботом']);   // как в шашки.html: этого узла в разметке нет

  const документ = {
    getElementById: function (id) {
      if (нетТакихУзлов.has(id)) {
        return созданные.find(function (у) { return у.id === id; }) || null;
      }
      if (!узлы[id]) {
        узлы[id] = сделатьУзел(id);
        if (id === 'доска') узлы[id].parentElement = сделатьУзел('рамка-доски');
      }
      return узлы[id];
    },
    createElement: function () {
      const у = сделатьУзел('');
      созданные.push(у);
      return у;
    },
    createDocumentFragment: function () { return сделатьУзел('фрагмент'); },
    querySelector: function () { return null; },
    querySelectorAll: function () { return []; },
    addEventListener: function () {},
    body:сделатьУзел('body')
  };

  const память = {
    getItem: function (к) { return хранилище.has(к) ? хранилище.get(к) : null; },
    setItem: function (к, з) { хранилище.set(к, String(з)); },
    removeItem: function (к) { хранилище.delete(к); }
  };

  const окно = {
    document: документ,
    localStorage: память,
    console: console,
    Date: Date, Math: Math, JSON: JSON, Set: Set, Map: Map, Array: Array, Object: Object,
    Promise: Promise, Number: Number, String: String, Boolean: Boolean, Error: Error,
    performance: { now: function () { return Date.now(); } },
    navigator: {},
    setTimeout: function (ф, мс) { очередь.push({ ф: ф, когда: времяТаймеров + (мс || 0), н: очередь.length }); return очередь.length; },
    clearTimeout: function () {},
    setInterval: function () { return 0; },
    clearInterval: function () {},
    addEventListener: function (тип, ф) { (слушателиОкна[тип] = слушателиОкна[тип] || []).push(ф); },
    removeEventListener: function () {},
    /* Общий лист «⋯»: берём у него дверь «завершить» — ту же, что жмёт человек. */
    ЛистЕщё: {
      подключить: function (опции) {
        окно.опцииЛиста = опции;
        return { освежитьКнопкуНастроек: function () {}, спроситьЗавершить: function () { return false; } };
      }
    },
    ШашкиРежимы: {
      показано: 0,
      показать: function () {},
      показатьПоИмени: function () {},
      показатьДоску: function () { окно.ШашкиРежимы.показано++; }
    }
  };
  окно.window = окно;
  окно.self = окно;
  const контекст = vm.createContext(окно);

  function запустить(файл) {
    vm.runInContext(fs.readFileSync(файл, 'utf8'), контекст, { filename: файл });
  }
  запустить(путьПравил);
  запустить(путьБота);
  запустить(путьЭкрана);
  if (настройки && настройки.лобби) запустить(путьЛобби);

  const страница = {
    окно: окно,
    правила: окно.ШашкиПравила,
    нажать: function (id) { документ.getElementById(id).click(); },
    /** Тап пальцем по полю доски. */
    тап: function (поле) {
      документ.getElementById('доска').запустить('click', {
        target: { closest: function () { return { getAttribute: function () { return поле; } }; } }
      });
    },
    /** Ход человека: первый из законных ходов позиции, что лежит сейчас в записи. */
    походитьПервымЗаконным: function () {
      const з = страница.запись();
      const позиция = страница.правила.партияИзКартинки(з.картинка, з.ходит);
      const ход = страница.правила.возможныеХоды(позиция)[0];
      ход.путь.forEach(function (поле) { страница.тап(поле); });   // путь начинается с исходной клетки
    },
    /** Бот думает и показывает ход через таймеры — прокручиваем их до конца. */
    прокрутить: function () {
      let шагов = 0;
      while (очередь.length && шагов++ < 200000) {
        очередь.sort(function (а, б) { return а.когда - б.когда || а.н - б.н; });
        const т = очередь.shift();
        времяТаймеров = Math.max(времяТаймеров, т.когда);
        т.ф();
      }
    },
    /** Событие окна, как его шлёт общее/js/telegram.js. */
    событие: function (имя) { (слушателиОкна[имя] || []).forEach(function (ф) { ф({}); }); },
    плашка: function () { return созданные.find(function (у) { return у.id === 'кнопка-доиграть-с-ботом'; }) || null; },
    запись: function () {
      const сырое = хранилище.get(КЛЮЧ);
      if (!сырое) return null;
      try { return JSON.parse(сырое); } catch (ошибка) { return null; }
    }
  };
  return страница;
}

/** Партия с ботом: уровень «лёгкий», свой ход c3–d4, потом ответ бота. */
function сыгратьХодСБотом(страница) {
  страница.нажать('уровень-лёгкий');
  страница.нажать('кнопка-с-ботом');
  страница.тап('c3');
  страница.тап('d4');
  страница.прокрутить();
}

