/* Проверка без браузера: партия шашек (с ботом и «вдвоём на этом устройстве»)
   переживает закрытие страницы — как у дурака (botgame_durak).

   Экран и лобби запускаются в песочнице vm с поддельным DOM и общей
   «памятью» (localStorage). «Перезагрузка» — это новая песочница на той же
   памяти. Правила и бот — настоящие, из js/.

   Запуск:  node tests/шашки-партия-сохраняется.js [игры/шашки/шашки-экран.js] [игры/шашки/шашки-лобби.js]
   Пути нужны для «красного» запуска: проверка на КОПИЯХ, где сохранение
   сломали, обязана упасть. Настоящие файлы портить нельзя.

   Ноль найденного — провал: каждая проверка сначала требует, чтобы нужное
   нашлось (запись в памяти, плашка, узел). */

