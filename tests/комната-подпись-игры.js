const КОРЕНЬ = path.join(__dirname, '..');

function довод(имя) {
  const найден = process.argv.find(function (д) { return д.indexOf('--' + имя + '=') === 0; });
  return найден ? найден.slice(имя.length + 3) : '';
}

const ЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;

const проверки = [];
function проверить(условие, текст) {
  проверки.push({ ок: Boolean(условие), текст: текст });
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + текст);
}

/* ---------------------------------------------------------------------
   Ломающая копия — во временной папке ОС, файл проекта не трогаем.
   --------------------------------------------------------------------- */
function заменитьИлиУпасть(текст, что, наЧто, файл) {
  if (текст.indexOf(что) === -1) {
    throw new Error('не нашёл в ' + файл + ' строку «' + что + '» — ломающий приём устарел, поправь его');
  }
  return текст.replace(что, наЧто);
}

/** Жёсткое «Подкидной» для ЛЮБОЙ игры — тот самый баг из задачи штаба. */
function приготовитьЛомающуюКопию(папка) {
  const текст = заменитьИлиУпасть(
    fs.readFileSync(path.join(КОРЕНЬ, 'js', 'дурак-комната.js'), 'utf8'),
    'function правилаИгрыСтрокой(игра, переводной, колода, вид) {',
    "function правилаИгрыСтрокой(игра, переводной, колода, вид) { return 'Подкидной'; " +
      '/* сломано нарочно ломающим прогоном — жёсткая «Подкидной» для любой игры */',
    'js/дурак-комната.js');
  const путь = path.join(папка, 'дурак-комната-сломана.js');
  fs.writeFileSync(путь, текст, 'utf8');
  return путь;
}

