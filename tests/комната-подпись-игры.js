/* =====================================================================
   ПОДПИСЬ РЕЖИМА И ПРАВИЛ В ОБЩЕЙ КОМНАТЕ — ПО ИГРЕ СТОЛА.

   Задача штаба: js/дурак-комната.js стоит не только у дурака (её же
   через js/онлайн-лобби.js подключают нарды и шашки), но раньше ВСЕГДА
   писала слова дурака — «Подкидной» и «С друзьями · Каждый за себя»,
   даже за столом нард или шашек. Теперь строки #комната-режим и
   #комната-правила берутся по вид.игра (правилаИгрыСтрокой в
   js/дурак-комната.js):
     дурак    — как раньше: подкидной/переводной + число карт,
                «Каждый за себя»/«2 на 2»;
     нарды    — «Нарды» (+ « · Короткие»/« · Длинные», если сервер
                прислал вид.вариантНард — сейчас в комнате ожидания
                этого поля нет, оно готово на будущее);
     шашки    — «Шашки»;
     шахматы  — «Шахматы» (+ « · <контроль>», если вид.контрольШахмат
                прислан — у общей комнаты дурака шахматы сейчас не
                стоят, ветка на будущее);
     остальные — название из js/игры-реестр.js (например «Морской бой»);
                нет записи в реестре — честная пустая строка, а не
                выдуманное имя;
     катан/монополия/домино/деберц — свои строки правил без изменений
                (регресс: их отдельно проверяли раньше, здесь просто
                убеждаемся, что новая ветка их не задела).
   У ЛЮБОЙ игры, кроме дурака, пилюля — просто «С друзьями», без
   «Каждый за себя»/«2 на 2»: это понятия только дурака (парами там
   играют по-настоящему, у остальных игр вид.парами сервер не
   выставляет).

   А) Модель: js/дурак-комната.js create({}).собрать(вид) — без DOM,
      прямой require, как tests/подбор-переключатель-модель.js.
   Б) Страница: показать() в поддельном DOM (tests/поддельный-браузер.js)
      — узлы #комната-режим/#комната-правила берём по id из index.html,
      второй копии разметки не заводим; не нашли узлы — проверка падает
      сама, не тихо пропускает.

   Запуск:
       node tests/комната-подпись-игры.js
   Свой файл вместо js/дурак-комната.js (проверка читает его):
       node tests/комната-подпись-игры.js --комната=<путь>

   Ломающий прогон (копия во временной папке ОС, файл проекта не
   трогаем — сам прогон и создаёт копию):
       node tests/комната-подпись-игры.js --сломать
   Правит копию так, что правилаИгрыСтрокой() СРАЗУ возвращает жёсткое
   «Подкидной» для любой игры (ровно баг из задачи штаба) — те же
   проверки А и Б на этой копии обязаны покраснеть на нардах/шашках.

   Выход 0 — провалов нет, 1 — есть.
   ===================================================================== */

const fs = require('fs');
