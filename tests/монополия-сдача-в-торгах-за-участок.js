/* С9. Партия из двух игроков: сдача кончает партию, аукцион не висит. */
for (const кто of [А, Б]) {
  сценарий('С9 два игрока, сдался ' + ИМЯ[кто], () => {
    const и = 'С9 сдался ' + ИМЯ[кто];
    const g = торги(2, 190 + кто, [30]);
    отметить(идутТорги(g) && g.auction.high === А && g.auction.actor === Б, и + ': раскладка верна — лидер А (30), ход у Б');
    P.action(g, кто, { type: 'surrender' });
    const живой = кто === А ? Б : А;
    отметить(g.phase === 'finished' && g.winner === живой && P.who(g) === -1, и + ': партия кончена, победил ' + ИМЯ[живой]);
    отметить(g.auction === null && g.queue.length === 0, и + ': аукциона нет, очередь пуста (' + g.queue.length + ')');
    отметить(g.properties[ЛОТ].owner === -1 && g.players[живой].money === НАЧАЛО, и + ': участок в банке, с победителя ничего не списано');
    let ошибка = null;
    try {
      P.assert(g);
    } catch (e) {
      ошибка = e;
    }
    отметить(!ошибка, и + ': сохранённая партия проходит assert' + (ошибка ? ' (' + ошибка.message + ')' : ''));
  });
}
