function внутри(папка, корень) {
  const от = path.relative(path.resolve(корень), path.resolve(папка));
  return !от.startsWith('..') && !path.isAbsolute(от);
}

function сделатьЛомающуюКопию(папкаКопии, номер) {
  const п = ПОЛОМКИ[номер - 1];
  if (!п) throw new Error('нет поломки с номером ' + номер + ' (есть 1..' + ПОЛОМКИ.length + ')');
  const папка = path.resolve(папкаКопии);
  if (внутри(папка, КОРЕНЬ)) throw new Error('копию нельзя класть внутрь проекта: ' + папка);
  if (!внутри(папка, os.tmpdir())) throw new Error('копия — только во временной папке системы (' + os.tmpdir() + '): ' + папка);
  const текст = fs.readFileSync(ПРАВИЛА_ПРОЕКТА, 'utf8').replace(/\r\n/g, '\n');
  const вхождений = текст.split(п.было).length - 1;
  if (вхождений !== 1) {
    throw new Error('приём порчи №' + номер + ' устарел: ожидалось ровно одно вхождение куска правил, нашлось ' + вхождений);
  }
  fs.mkdirSync(папка, { recursive: true });
  fs.copyFileSync(ДАННЫЕ_ПРОЕКТА, path.join(папка, 'монополия-данные.js'));
  const копия = path.join(папка, 'монополия-правила.js');
  fs.writeFileSync(копия, текст.replace(п.было, () => п.стало), 'utf8');
  // Последний рубеж: подключать будем только файл вне проекта
  if (внутри(копия, КОРЕНЬ)) throw new Error('копия оказалась внутри проекта: ' + копия);
  return копия;
}

