const А = 0, Б = 1, В = 2, Г = 3;
const ИМЯ = ['А', 'Б', 'В', 'Г'];
const ЛОТ = 1; // участок, который А отказался покупать
const НАЧАЛО = 1500; // деньги каждого игрока на старте партии
/* У каждого своя собственность — чтобы после сдачи было что выставлять
   на аукцион и было видно, что это идёт ПОСЛЕ текущих торгов. */
const СВОЁ = { [А]: [3], [Б]: [12], [В]: [5, 15], [Г]: [25] };

/* А стоит на ничейном участке ЛОТ и отказывается покупать — начинаются
   торги за участок, в них все живые, ход у А, дальше по кругу.
   Ходы: число — ставка, 'пас' — пас, по очереди тех, чей ход. */
function торги(n, seed, ходы) {
  const g = P.create(n, seed);
  for (let i = 0; i < n; i++)
    for (const id of СВОЁ[i] || []) g.properties[id].owner = i;
  g.turn = А;
  g.players[А].position = ЛОТ;
  g.queue = [{ kind: 'buy', from: А, id: ЛОТ }];
  g.phase = 'buy';
  P.action(g, А, { type: 'auction' });
  for (const х of ходы) {
    const кто = P.who(g);
    P.action(g, кто, х === 'пас' ? { type: 'pass' } : { type: 'bid', amount: х });
  }
  return g;
}
const идутТорги = (g) => g.phase === 'auction' && g.auction && !g.auction.building && g.auction.id === ЛОТ;

/* Два пути выбытия: настоящая сдача и флаг out (партия из памяти,
   оживляется при загрузке — assert). */
const ПУТИ = ['сдача', 'флаг'];
function выбыть(g, p, путь) {
  if (путь === 'сдача') P.action(g, p, { type: 'surrender' });
  else {
    g.players[p].out = true;
    P.assert(g);
  }
}
/* Итог торгов за ЛОТ: идут — их состояние; кончились — чем. */
function итог(g) {
  if (идутТорги(g)) {
    const a = g.auction;
    return {
      идут: true,
      high: a.high,
      bid: a.bid,
      bids: a.bids,
      actor: a.actor,
      eligible: a.eligible.slice().sort(),
      passed: a.passed.slice().sort(),
    };
  }
  return { идут: false, победа: победаЗаЛот(g), владелец: g.properties[ЛОТ].owner };
}
function победаЗаЛот(g) {
  const е = g.events.find((e) => e.kind === 'auctionWin' && e.id === ЛОТ);
  return е ? { player: е.player, amount: е.amount } : null;
}
const строка = (x) => JSON.stringify(x);

/* Доиграть торги за ЛОТ: у кого в плане ставка — ставит её, если она
   выше текущей и он не лидер; остальные пасуют. */
function доиграть(g, план = {}) {
  let шагов = 0;
  while (идутТорги(g) && шагов++ < 30) {
    const кто = P.who(g), a = g.auction;
    if (план[кто] > a.bid && a.high !== кто) P.action(g, кто, { type: 'bid', amount: план[кто] });
    else P.action(g, кто, { type: 'pass' });
  }
}

/* Итог по деньгам и участку сразу после торгов за ЛОТ. Выбывшим:
   флагом — деньги как были, сдачей — всё ушло банку (0), но за ставку
   ничего не списано и участок им не достался. */
function проверитьИсход(g, и, путь, выбывшие, победитель, ставка) {
  отметить(!идутТорги(g), и + ': торги за участок закончены');
  const п = победаЗаЛот(g);
  if (победитель === -1) {
    отметить(!п && g.properties[ЛОТ].owner === -1, и + ': участок остался в банке (' + строка(п) + ', владелец ' + g.properties[ЛОТ].owner + ')');
  } else {
    отметить(п && п.player === победитель && п.amount === ставка, и + ': участок выиграл ' + ИМЯ[победитель] + ' за ' + ставка + ' (' + строка(п) + ')');
    отметить(g.properties[ЛОТ].owner === победитель, и + ': владелец участка — ' + ИМЯ[победитель] + ' (' + g.properties[ЛОТ].owner + ')');
  }
  const деньги = g.players.map((pl) => pl.money);
  const ждём = g.players.map((_, i) => {
    if (выбывшие.includes(i)) return путь === 'сдача' ? 0 : НАЧАЛО;
    return i === победитель ? НАЧАЛО - ставка : НАЧАЛО;
  });
  отметить(строка(деньги) === строка(ждём), и + ': деньги — списана ровно ставка победителя, у выбывших за ставку ничего (' + строка(деньги) + ', ждём ' + строка(ждём) + ')');
  отметить(!выбывшие.includes(g.properties[ЛОТ].owner), и + ': участок не достался выбывшему');
}

/* Партия после всех торгов живая: пропасовать аукционы участков
   сдавшегося; после этого нет аукциона, очередь пуста, assert и who
   не падают, ход у живого (или партия честно кончена). */
function проверитьЧтоПартияИдёт(g, и, конецПартии = false) {
  let шагов = 0;
  while (g.phase === 'auction' && шагов++ < 40) P.action(g, P.who(g), { type: 'pass' });
  let ошибка = null;
  try {
    P.assert(g);
    const кто = P.who(g);
    if (конецПартии) {
      if (g.phase !== 'finished' || кто !== -1) throw Error('партия не кончена');
    } else if (кто < 0 || g.players[кто].out) throw Error('ход у ' + кто);
  } catch (e) {
    ошибка = e;
  }
  отметить(
    !ошибка && g.phase !== 'auction' && !g.auction && g.queue.length === 0,
    и + ': партия ' + (конецПартии ? 'кончена' : 'идёт дальше') + ' — торгов нет, очередь пуста (этап «' + g.phase + '», очередь ' + g.queue.length + (ошибка ? ', упало: ' + ошибка.message : '') + ')',
  );
}

console.log('Проверка: сдача посреди торгов за участок снимает только ставку сдавшегося (правила: ' + ПУТЬ_ПРАВИЛ + (ЛОМАТЬ ? ', это копия' : ', это файл проекта') + ')');

/* Каждый сценарий — обоими путями, со сверкой «один исход». */
function обаПути(название, собрать, кто, проверить) {
  const итоги = {};
  const выбывшие = [].concat(кто);
  for (const путь of ПУТИ) {
    сценарий(название + ' [' + путь + ']', () => {
      const g = собрать();
      отметить(идутТорги(g), название + ' [' + путь + ']: раскладка верна — идут торги за участок');
      for (const p of выбывшие) выбыть(g, p, путь);
      отметить(выбывшие.every((p) => g.players[p].out === true), название + ' [' + путь + ']: выбывшие выбыли');
      итоги[путь] = итог(g);
      проверить(g, название + ' [' + путь + ']', путь, выбывшие);
    });
  }
  отметить(
    итоги.сдача !== undefined && строка(итоги.сдача) === строка(итоги.флаг),
    название + ': сдача и флаг ведут к одному исходу (' + строка(итоги.сдача) + ' / ' + строка(итоги.флаг) + ')',
  );
}

/* С1. Ушёл лидер, второй жив: лидер — лучшая живая ставка, торги идут. */
for (const n of [3, 4]) {
  обаПути('С1 ушёл лидер, второй жив, ' + n + ' игрока', () => торги(n, 100 + n, [30, 50, 100]), В, (g, и, путь, вышли) => {
    const a = g.auction;
    отметить(идутТорги(g), и + ': торги за участок идут дальше');
    отметить(a && a.high === Б && a.bid === 50, и + ': лидер — Б со своей ставкой 50, не с нуля (' + (a && a.high) + ', ' + (a && a.bid) + ')');
    отметить(a && строка(a.bids) === строка({ [А]: 30, [Б]: 50 }), и + ': ставки живых целы, ставки В нет (' + строка(a && a.bids) + ')');
    отметить(a && !a.eligible.includes(В), и + ': В нет среди участников');
    доиграть(g, { [А]: 51 });
    проверитьИсход(g, и, путь, вышли, А, 51);
    проверитьЧтоПартияИдёт(g, и);
  });
}

