/* =====================================================================
   МОНОПОЛИЯ: СДАЧА ПОСРЕДИ ТОРГОВ ЗА УЧАСТОК — СНИМАЕТСЯ ТОЛЬКО СТАВКА
   СДАВШЕГОСЯ.

   Решение владельца 30.09: «во время торгов при сдаче снимать только
   ставку сдавшегося». Для торгов за здание это уже было; раньше торги
   за УЧАСТОК при любой сдаче сгорали и начинались с нуля, уезжали в
   конец очереди, а если сдавался тот, кто отказался покупать участок,
   торги пропадали вовсе и участок молча оставался в банке. Теперь:
     1) выбыл участник — снимаются его ставка и место; лидер — лучшая
        живая ставка; нет таких — торги с начальной цены; ход был у
        выбывшего — идёт следующему живому; остался один со ставкой и
        торговаться некому — участок ему по его ставке; торговаться
        некому вовсе — участок в банке («Участок остался в банке»);
     2) текущие торги доигрываются ПЕРВЫМИ, участки сдавшегося идут с
        аукциона после них;
     3) сдался отказавшийся покупать — торги не пропадают;
     4) с выбывшего ничего не списывается, участок ему не достаётся;
     5) сдача кнопкой и выбытие флагом out (партия из памяти) — один исход.

   Правила общие для браузера и сервера: проверяем сам файл
   js/монополия-правила.js (его же require'ит сервер). Только node.

   Запуск:
       node tests/монополия-сдача-в-торгах-за-участок.js
       node tests/монополия-сдача-в-торгах-за-участок.js --сломать [папка] [номер]
       node tests/монополия-сдача-в-торгах-за-участок.js --сломать-все [папка]

   --сломать [папка] [номер] — копирует правила (с файлом данных) в папку
   внутри временной папки системы (os.tmpdir()) и портит в КОПИИ одно
   место (список ПОЛОМКИ, по умолчанию №1 — «сдача начинает торги за
   участок с нуля»); проверка на копии обязана покраснеть (выход 1).
   Без папки — новая папка в os.tmpdir(). Папка внутри проекта или вне
   временной папки — ошибка запуска (выход 2). Замена, не нашедшая свой
   кусок правил ровно один раз, — тоже ошибка запуска (выход 2).
   --сломать-все [папка] — обычный прогон плюс все поломки по очереди;
   краснеет сам, если хоть одна поломка не покраснела.
   Настоящий файл правил не портится никогда.
   ===================================================================== */

