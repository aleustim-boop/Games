'use strict';

/* =====================================================================
   ШАШКИ И НАРДЫ КАК ДУРАК: СНИМКИ ДЛЯ СРАВНЕНИЯ ГЛАЗАМИ + ПРОВЕРКА УЗЛОВ.

   Что делает: на ширинах 390 и 320 снимает лобби шашек и лобби нард, а на
   390 — плашку итога после победы над ботом у каждой. Победу ставим без
   долгой партии:
     - шашки: подменяем одну дверь правил (создатьПартию отдаёт позицию
       «белая шашка бьёт последнюю чёрную»), дальше ходит живой палец;
     - нарды: подменяем создатьПартию так, что партия сразу завершена
       победой белых (честный приём «забег закончен»); плашку рисует сам экран.
   Снимки — в tests/снимки/шашки-нарды-как-дурак/ .

   Кроме снимков проверяет узлы: ноль найденного — провал, а не пропуск.
   Лобби: аватар, рейтинг, место, подпись под картинкой, вход «Играть с
   ботами», нет старой серии. Итог: «Играть ещё», «Реванш», «Сыграть с
   ботом», «Похвастаться», «Рекорды», «В меню», «итог-рейтинга»; у нард нет
   «кнопка-другой-соперник».

   Запуск (файловый сервер уже поднят, порт свой, не 8790):
       node tests/шашки-нарды-снимки-как-дурак.js 8923
   Ломающий запуск — на КОПИИ проекта во временной папке: поднять сервер
   (КОРЕНЬ_СЕРВЕРА=<копия> node tests/локальный-сервер.js <порт>), убрать в
   копии шашки.html id="лобби-аватар", запустить на порт копии — краснеет.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const { chromium, подготовитьПодделку } = require('./браузер-робот.js');

const ПОРТ = Number(process.argv.slice(2).find((а) => /^\d+$/.test(а))) || 8080;
const ОСНОВА = 'http://127.0.0.1:' + ПОРТ + '/';
const ПАПКА = path.join(__dirname, 'снимки', 'шашки-нарды-как-дурак');
// Белая шашка c3 бьёт чёрную d4 и ставит на e5; у чёрных после этого шашек нет.
const КАРТИНКА_ШАШЕК = ['........', '........', '........', '........', '...ч....', '..б.....', '........', '........'];

let всего = 0;
let провалов = 0;
function проверить(условие, слова) {
  всего++;
  console.log((условие ? '  ок      ' : '  ПРОВАЛ  ') + слова);
  if (!условие) провалов++;
}
const спать = (мс) => new Promise((ф) => setTimeout(ф, мс));

async function открыть(браузер, ширина, высота, файл, подмена) {
  const окно = await браузер.newContext({ viewport: { width: ширина, height: высота }, hasTouch: true, deviceScaleFactor: 2 });
  const страница = await окно.newPage();
  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
    if (/Failed to load resource/.test(м.text())) return;
    красные.push('консоль: ' + м.text());
  });
  await подготовитьПодделку(страница, { версия: '8.0' });
  if (подмена === 'шашки') {
    await страница.addInitScript((картинка) => {
      let настоящие = null;
      Object.defineProperty(window, 'ШашкиПравила', {
        configurable: true,
        get() { return настоящие; },
        set(з) {
          настоящие = з;
          if (з && typeof з.партияИзКартинки === 'function') {
            const было = з.создатьПартию;
            з.создатьПартию = function () {
              try { return з.партияИзКартинки(картинка, з.БЕЛЫЕ); } catch (с) { return было.apply(this, arguments); }
            };
          }
        }
      });
    }, КАРТИНКА_ШАШЕК);
  }
  if (подмена === 'нарды') {
    await страница.addInitScript(() => {
      let настоящие = null;
      Object.defineProperty(window, 'НардыПравила', {
        configurable: true,
        get() { return настоящие; },
        set(з) {
          настоящие = з;
          if (з && typeof з.создатьПартию === 'function') {
            const было = з.создатьПартию;
            з.создатьПартию = function () {
              const п = было.apply(this, arguments);
              п.завершена = true;
              п.победитель = з.БЕЛЫЕ;
              п.цена = 1;
              п.видПобеды = 'обычная';
              п.причина = 'Все фишки белых вынесены';
              return п;
            };
          }
        }
      });
    });
  }
  await страница.goto(ОСНОВА + файл);
  await спать(700);
  return { окно, страница, красные };
}

async function виден(страница, селектор) {
  return страница.evaluate((с) => {
    const у = document.querySelector(с);
    if (!у) return { есть: false, виден: false };
    const р = у.getBoundingClientRect();
    return { есть: true, виден: р.width > 0 && р.height > 0 && у.offsetParent !== null };
  }, селектор);
}
async function нужныеУзлы(страница, метка, селекторы) {
  for (const [имя, с] of селекторы) {
    const р = await виден(страница, с);
    проверить(р.есть && р.виден, метка + ': «' + имя + '» (' + с + ') найден и виден');
  }
}
async function нужныеУзлыЕсть(страница, метка, селекторы) {
  for (const [имя, с] of селекторы) {
    const р = await виден(страница, с);
    проверить(р.есть, метка + ': «' + имя + '» (' + с + ') найден');
  }
}
async function снять(страница, имяФайла) {
  const п = path.join(ПАПКА, имяФайла);
  await страница.screenshot({ path: п });
  const размер = fs.existsSync(п) ? fs.statSync(п).size : 0;
  проверить(размер > 1000, 'снимок записан: tests/снимки/шашки-нарды-как-дурак/' + имяФайла + ' (' + размер + ' байт)');
}
async function нажать(страница, id) {
  return страница.evaluate((и) => { const к = document.getElementById(и); if (!к) return false; к.click(); return true; }, id);
}

(async () => {
  fs.mkdirSync(ПАПКА, { recursive: true });
  console.log('Шашки и нарды как дурак — снимки. Основа: ' + ОСНОВА);
  const браузер = await chromium.launch();
  const игры = [['шашки', 'шашки.html'], ['нарды', 'нарды.html']];

  for (const [ширина, высота] of [[390, 844], [320, 568]]) {
    for (const [имя, файл] of игры) {
      console.log('\n=== Ширина ' + ширина + ': лобби ' + имя + ' ===');
      const { окно, страница, красные } = await открыть(браузер, ширина, высота, файл, null);
      const м = 'лобби ' + имя + ' ' + ширина;
      await нужныеУзлы(страница, м, [
        ['аватар', '#экран-лобби #лобби-аватар'],
        ['подпись под картинкой', '#экран-лобби .лобби__подпись'],
        ['играть с ботами', '#лобби-боты'],
        ['игра онлайн', '#лобби-найти-игру']
      ]);
      await нужныеУзлыЕсть(страница, м, [
        ['рейтинг', '#экран-лобби #лобби-рейтинг'],
        ['место', '#экран-лобби #лобби-место']
      ]);
      const название = await страница.evaluate(() => (document.querySelector('#лобби-боты .карточка-входа__название') || {}).textContent || '');
      проверить(название.trim() === 'Играть с ботами', м + ': вход называется «Играть с ботами» (вышло «' + название.trim() + '»)');
      проверить((await страница.$$('#лобби-серия-текст')).length === 0, м + ': старой серии «лобби-серия-текст» нет');
      const шире = await страница.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1);
      проверить(!шире, м + ': страница не шире окна');
      await снять(страница, 'лобби-' + имя + '-' + ширина + '.png');
      проверить(красные.length === 0, м + ': консоль чистая' + (красные.length ? ' — ' + красные.join(' | ') : ''));
      await окно.close();
    }
  }

  for (const [имя, файл] of игры) {
    console.log('\n=== Ширина 390: плашка итога ' + имя + ' после победы над ботом ===');
    const { окно, страница, красные } = await открыть(браузер, 390, 844, файл, имя);
    const м = 'итог ' + имя;
    проверить(await нажать(страница, 'лобби-боты'), м + ': карточка «Играть с ботами» нажата');
    await спать(400);
    проверить(await нажать(страница, 'кнопка-с-ботом'), м + ': кнопка начала партии нажата');
    await спать(900);
    if (имя === 'шашки') {
      const наДоске = await страница.evaluate(() => document.querySelectorAll('[data-поле] .шашка, [data-поле] .фишка').length);
      console.log('  фишек на доске по селектору: ' + наДоске);
      for (const поле of ['c3', 'e5']) {
        await страница.evaluate((п) => { const к = document.querySelector('[data-поле="' + п + '"]'); if (к) к.click(); }, поле);
        await спать(300);
      }
      await спать(900);
    }
    const итог = await страница.evaluate(() => {
      const э = document.getElementById('экран-итога');
      const з = document.getElementById('заголовок-итога');
      return { виден: !!э && э.classList.contains('экран--виден'), заголовок: з ? з.textContent.trim() : '' };
    });
    проверить(итог.виден, м + ': плашка итога появилась (заголовок: «' + итог.заголовок + '»)');
    if (имя === 'шашки') проверить(/выиграл|победил|победа/i.test(итог.заголовок), м + ': заголовок про победу, вышло «' + итог.заголовок + '»');
    await нужныеУзлыЕсть(страница, м, [
      ['Играть ещё', '#экран-итога #кнопка-ещё'],
      ['Реванш', '#экран-итога #кнопка-реванш'],
      ['Сыграть с ботом', '#экран-итога #кнопка-ещё-с-ботом'],
      ['Похвастаться', '#экран-итога #кнопка-похвастаться'],
      ['Рекорды', '#экран-итога #кнопка-рекорды-итог'],
      ['итог-рейтинга', '#экран-итога #итог-рейтинга']
    ]);
    await нужныеУзлы(страница, м, [
      ['Играть ещё', '#экран-итога #кнопка-ещё'],
      ['Рекорды', '#экран-итога #кнопка-рекорды-итог'],
      ['В меню', '#экран-итога #кнопка-в-меню-итог']
    ]);
    const старая = (await страница.$$('#экран-итога #кнопка-другой-соперник')).length;
    if (имя === 'нарды') проверить(старая === 0, м + ': старой кнопки «кнопка-другой-соперник» нет');
    const видимые = await страница.evaluate(() =>
      Array.from(document.querySelectorAll('#экран-итога button')).filter((к) => к.offsetParent !== null).map((к) => к.textContent.trim()));
    console.log('  видимые кнопки итога: ' + JSON.stringify(видимые));
    await снять(страница, 'итог-победа-' + имя + '-390.png');
    проверить(красные.length === 0, м + ': консоль чистая' + (красные.length ? ' — ' + красные.join(' | ') : ''));
    await окно.close();
  }

  await браузер.close();
  console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
})().catch((сбой) => {
  console.log('проверка сломалась: ' + сбой.message);
  process.exit(2);
});
