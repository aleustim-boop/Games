async function прогнатьОдно(браузер, адрес, размер, мест, св, папка) {
  const { вид, фазаВиде, местаВиде } = собратьВид(мест, св);
  const контекст = await браузер.newContext({ viewport: { width: размер.w, height: размер.h }, reducedMotion: 'reduce' });
  const ошибки = [];
  const страница = await контекст.newPage();
  страница.on('pageerror', function (о) { ошибки.push('исключение: ' + о.message); });
  страница.on('console', function (с) { if (с.type() === 'error' && !/Failed to load resource/.test(с.text())) ошибки.push('консоль: ' + с.text()); });
  await подготовитьПодделку(страница, {});
  try {
    await страница.goto(адрес + 'деберц.html?сервер=' + encodeURIComponent('http://127.0.0.1:1'));
    await страница.waitForFunction(function () { return window.ИграПоСети && window.ЛистЕщё && window.ДеберцОтсчёт; }, null, { timeout: 8000 });
    await страница.waitForTimeout(400);
    const ошПоказа = await страница.evaluate(показатьСтол, вид);
    await страница.waitForTimeout(1500);   // раздача и раскладка; затем ещё тик секундных часов
    const файл = path.join(папка, размер.w + '-' + мест + 'места-' + св.ключ + '.png');
    await страница.screenshot({ path: файл });
    console.log('  снимок: ' + файл);
    const м = await страница.evaluate(замерить);
    разобрать(св, мест, размер, { м: м, ошибки: ошибки, ошПоказа: ошПоказа, фазаВиде: фазаВиде, местаВиде: местаВиде });
  } finally {
    await контекст.close();
  }
}

async function прогнать(подменаСтиля, папка) {
  fs.mkdirSync(папка, { recursive: true });
  const сервер = await поднятьСерверФайлов(подменаСтиля);
  const адрес = 'http://127.0.0.1:' + сервер.address().port + '/';
  console.log('=== Деберц: отсчёт минуты на ход — снимки и замеры ===');
  console.log('файлы: ' + адрес + (подменаСтиля ? '  (стиль подменён: ' + подменаСтиля + ')' : '') + '\nснимки: ' + папка);
  let браузер = null;
  try {
    браузер = await chromium.launch();
    for (const размер of РАЗМЕРЫ) {
      for (const св of СОСТОЯНИЯ) {
        for (const мест of св.места) {
          console.log('\n--- ' + размер.w + '×' + размер.h + ' · ' + мест + ' места · ' + св.ключ + ' ---');
          await прогнатьОдно(браузер, адрес, размер, мест, св, папка);
        }
      }
    }
  } finally {
    if (браузер) await браузер.close();
    сервер.close();
    fs.rmSync(process.env.ДАННЫЕ_ИГРЫ, { recursive: true, force: true });
    console.log('\nСервер файлов закрыт.');
  }
  console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
  process.exitCode = провалов > 0 ? 1 : 0;
}

/* ---------- Ломающий прогон: порча КОПИЙ style-деберц.css ---------- */

const ПОРЧИ = [
  { заголовок: 'пилюля уезжает за правый край экрана (копия стиля)', метка: М_ПИЛЮЛЯ,
    было: '.деберц #подсказка .деберц-отсчёт { position: absolute; right: 8px;',
    стало: '.деберц #подсказка .деберц-отсчёт { position: absolute; right: -60px;' },
  { заголовок: 'пометка «играет бот» обрезана по ширине (копия стиля)', метка: М_БОТ,
    было: '.деберц .деберц-участник__бот { font-style: normal;',
    стало: '.деберц .деберц-участник__бот { display: block; width: 14px; font-style: normal;' }
];

function ломатьОдной(порча, счёт) {
  console.log('=== Ломающий прогон: ' + порча.заголовок + ' — обязана покраснеть на ' + порча.метка + ' ===');
  счёт.всего++;
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'деберц-время-лом-'));
  try {
    const текст = fs.readFileSync(path.join(ПРОЕКТ, ИМЯ_СТИЛЯ), 'utf8');
    const вхождений = текст.split(порча.было).length - 1;
    if (вхождений !== 1) {
      console.log('ПРОВАЛ: образец порчи найден в ' + ИМЯ_СТИЛЯ + ' ' + вхождений + ' раз (нужно ровно 1)');
      счёт.плохо++;
      return;
    }
    const копия = path.join(папка, ИМЯ_СТИЛЯ);
    fs.writeFileSync(копия, текст.replace(порча.было, () => порча.стало), 'utf8');
    console.log('Порченая копия стиля: ' + копия);
    const прогон = spawnSync(process.execPath, [__filename, '--стиль', копия, '--снимки', path.join(папка, 'снимки')], { encoding: 'utf8', timeout: 500000 });
    const плохие = (прогон.stdout || '').split('\n').filter(с => с.includes('ПЛОХО'));
    const наМетке = плохие.filter(с => с.includes(порча.метка));
    console.log(наМетке.slice(0, 3).join('\n') + (прогон.stderr ? '\nstderr: ' + прогон.stderr.slice(0, 300) : ''));
    const ок = прогон.status === 1 && наМетке.length > 0;
    console.log(ок ? 'ПОКРАСНЕЛ на ' + порча.метка + ' (красных строк метки: ' + наМетке.length + ', всего красных: ' + плохие.length + ')'
      : 'ПРОВАЛ: не покраснел на ' + порча.метка + ' (код ' + прогон.status + ')');
    if (!ок) счёт.плохо++;
  } finally {
    fs.rmSync(папка, { recursive: true, force: true });
  }
}

function ломать() {
  const счёт = { всего: 0, плохо: 0 };
  ПОРЧИ.forEach(порча => ломатьОдной(порча, счёт));
  console.log('\nИтого проверок: ' + счёт.всего + ', провалов: ' + счёт.плохо);
  process.exitCode = счёт.плохо ? 1 : 0;
}

function довод(имя) { const г = process.argv.indexOf(имя); return г !== -1 ? process.argv[г + 1] : null; }

if (process.argv.includes('--сломать')) ломать();
else {
  прогнать(довод('--стиль'), довод('--снимки') || path.join(ПРОЕКТ, 'tests', 'снимки', 'деберц-время')).catch(function (е) {
    console.error('ПРОВАЛ ЗАПУСКА: ' + (е && е.stack || е));
    process.exitCode = 1;
  });
}
