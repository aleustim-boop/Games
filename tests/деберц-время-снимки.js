const коорд = function (р) { return Math.round(р.x) + ',' + Math.round(р.y) + '–' + Math.round(р.r) + ',' + Math.round(р.b); };

function разобрать(св, мест, размер, р) {
  const п = размер.w + 'px · ' + мест + ' места · ' + св.ключ + ': ';
  const м = р.м;
  проверить(р.ошПоказа === '', п + 'стол показан через ИграПоСети.показатьВид' + (р.ошПоказа ? ' (' + р.ошПоказа + ')' : ''));
  проверить(р.фазаВиде === св.фаза, п + 'стол в нужной фазе «' + св.фаза + '» (вышло: ' + р.фазаВиде + ')');
  проверить(р.местаВиде === мест, п + 'за столом ' + мест + ' места (вышло: ' + р.местаВиде + ')');
  проверить(м.вбок <= 0, п + 'горизонтальной прокрутки нет (лишних пикселей: ' + м.вбок + ')');

  if (св.без) {
    // 8) часов нет — узлов отсчёта на виду быть не должно (спрятаны или вовсе не созданы).
    проверить(м.виднылиОтсчёты.length === 0, п + '[нет-отсчёта] ни одной пилюли и строки отсчёта на виду (на виду: ' + (м.виднылиОтсчёты.join('; ') || 'ничего') + ')');
    if (св.итог) {
      проверить(м.итогДействия.length > 0, п + '[нет-отсчёта] страховка: окно итога открыто, кнопка «Следующая сдача» на месте (кнопок: ' + м.итогДействия.length + ')');
    } else {
      проверить(м.плашка.есть && м.плашка.виден, п + '[нет-отсчёта] страховка: плашка #подсказка на экране (стол живой)');
      проверить(!/(^|\s)деберц-подсказка--есть-отсчёт(\s|$)/.test(м.плашка.классы || ''), п + '[нет-отсчёта] на плашке нет признака «есть-отсчёт» (классы: ' + м.плашка.классы + ')');
    }
  } else if (св.итог) {
    const у = м.узлы['деберц-итог-отсчёт'];
    if (проверить(у.есть && у.виден, п + '[итог-строка] строка #деберц-итог-отсчёт найдена и видна')) {
      const ждём = 'Следующая сдача начнётся через ' + св.секунд + ' с';
      проверить(у.текст.replace(/[\u00a0\u202f]/g, ' ') === ждём, п + '[итог-строка] слова «' + ждём + '» (вышло: «' + у.текст + '»)');
      проверить(у.вЭкране, п + '[итог-строка] строка целиком в экране (' + коорд(у) + ', экран ' + м.W + '×' + м.H + ')');
      проверить(у.сверху, п + '[итог-строка] строку ничто не перекрывает (в её середине: ' + у.чтоСверху + '; строка ' + коорд(у) + ')');
      проверить(!у.срезан, п + '[итог-строка] текст строки не обрезан');
      проверить(у.верхЧисла !== undefined && Math.abs(у.верхС - у.верхЧисла) < 1, п + '[итог-строка] «с» в одной строке с числом (верх числа ' + Math.round(у.верхЧисла) + ', верх «с» ' + Math.round(у.верхС) + ')');
      проверить(у.w > 0 && у.h < 80, п + '[итог-строка] строка не раздулась (высота ' + Math.round(у.h) + ')');
    }
    проверить(м.итогДействия.length > 0 && м.итогДействия.every(function (к) { return к.вЭкране && к.сверху; }),
      п + '[итог-строка] кнопки итога целиком в экране и не перекрыты (' + м.итогДействия.map(function (к) { return '«' + к.текст + '»'; }).join(', ') + ')');
  } else if (св.пилюля) {
    const у = м.узлы[св.пилюля];
    if (проверить(у.есть && у.виден, п + '[пилюля] пилюля #' + св.пилюля + ' найдена и видна')) {
      проверить(у.текст.replace(/[\u00a0\u202f]/g, ' ') === св.секунд + ' с', п + '[пилюля] в пилюле «' + св.секунд + ' с» (вышло: «' + у.текст + '»)');
      проверить(у.вЭкране, п + '[пилюля] пилюля целиком в экране (' + коорд(у) + ', экран ' + м.W + '×' + м.H + ')');
      проверить(у.сверху, п + '[пилюля] пилюлю ничто не перекрывает');
      проверить(!у.срезан, п + '[пилюля] текст пилюли не обрезан');
      проверить(у.строк === 1, п + '[пилюля] число и «с» в одной строке (строк: ' + у.строк + ')');
      проверить(Boolean(св.мало) === /деберц-отсчёт--мало/.test(у.классы), п + '[пилюля] ' + (св.мало ? 'у пилюли класс «мало»' : 'класса «мало» нет') + ' (классы: ' + у.классы + ')');
      проверить(Boolean(св.ход === 0) === /деберц-отсчёт--мой/.test(у.классы), п + '[пилюля] ' + (св.ход === 0 ? 'класс «мой» стоит' : 'класса «мой» нет') + ' (классы: ' + у.классы + ')');
      if (!св.окно) {
        const пл = м.плашка;
        проверить(пл.есть && пл.виден && внутри(у, пл), п + '[пилюля] пилюля целиком внутри плашки (пилюля ' + коорд(у) + ', плашка ' + (пл.есть ? коорд(пл) : 'нет') + ')');
        проверить(пл.есть && пл.x >= -0.5 && пл.r <= м.W + 0.5, п + '[пилюля] плашка целиком по ширине экрана (' + (пл.есть ? коорд(пл) : 'нет') + ')');
        проверить(/(^|\s)деберц-подсказка--есть-отсчёт(\s|$)/.test(пл.классы || ''), п + '[пилюля] на плашке признак «есть-отсчёт» (классы: ' + пл.классы + ')');
        if (!проверить(Boolean(м.чейХод), п + '[пилюля] в плашке есть «Ваш ход / Ходит …» (вышло: «' + (м.чейХод ? м.чейХод.текст : 'нет') + '»)')) { /* ниже нечего мерить */ }
        if (м.статусСлова) проверить(!пересекаются(м.статусСлова, у), п + '[пилюля] строка подсказки «' + м.статус.текст + '» не залезает под пилюлю (слова ' + коорд(м.статусСлова) + ', пилюля ' + коорд(у) + ')');
        if (м.чейХод) проверить(!пересекаются(м.чейХод, у), п + '[пилюля] слова «' + м.чейХод.текст + '» не залезают под пилюлю (слова ' + коорд(м.чейХод) + ', пилюля ' + коорд(у) + ')');
      }
    }
  }

  if (св.событие) {
    const с = м.статус;
    if (проверить(с.есть && с.виден, п + '[слова] строка #деберц-статус найдена и видна')) {
      проверить(с.текст.indexOf('время вышло') !== -1 && с.текст.indexOf('ход сделал бот') !== -1, п + '[слова] в статусе слова про время (вышло: «' + с.текст + '»)');
      проверить(!с.срезан, п + '[слова] слова не обрезаны');
      проверить(с.x >= -0.5 && с.r <= м.W + 0.5 && с.b <= м.H + 0.5, п + '[слова] статус целиком в экране (' + коорд(с) + ')');
    }
  }

  // Карточки соседей: только когда стол от трёх мест и это не окно итога (его закрывает окно).
  if (мест > 2 && !св.итог) {
    проверить(м.карточки.length === мест - 1, п + '[бот] карточек соседей ' + (мест - 1) + ' (найдено: ' + м.карточки.length + ')');
    м.карточки.forEach(function (к, i) {
      проверить(к.виден && к.вЭкране, п + '[бот] карточка соседа ' + (i + 1) + ' целиком в экране (' + коорд(к) + ')');
      проверить(к.дети.length > 0 && к.дети.every(function (д) { return д.внутри; }), п + '[бот] у соседа ' + (i + 1) + ' имя, роль и подписи целиком внутри карточки (' + к.дети.map(function (д) { return д.тег + '«' + д.текст + '»' + (д.внутри ? '' : ' ВНЕ ' + коорд(д.р)); }).join(', ') + '; карточка ' + коорд(к) + ')');
      проверить(к.дети.every(function (д) { return !д.срезан; }), п + '[бот] у соседа ' + (i + 1) + ' ни одна подпись не обрезана (' + к.дети.filter(function (д) { return д.срезан; }).map(function (д) { return '«' + д.текст + '»'; }).join(', ') + ')');
    });
    for (let a = 0; a < м.карточки.length; a++) for (let b = a + 1; b < м.карточки.length; b++) {
      проверить(!пересекаются(м.карточки[a], м.карточки[b]), п + '[бот] карточки соседей ' + (a + 1) + ' и ' + (b + 1) + ' не наезжают друг на друга');
    }
    const спящие = м.карточки.filter(function (к) { return к.спит; });
    if (св.спит) {
      if (проверить(спящие.length === 1, п + '[бот] ровно один спящий сосед (найдено: ' + спящие.length + ')')) {
        const бот = спящие[0].дети.filter(function (д) { return д.класс === 'деберц-участник__бот'; });
        if (проверить(бот.length === 1 && бот[0].тег === 'em', п + '[бот] на карточке спящего есть em.деберц-участник__бот (найдено: ' + бот.length + ')')) {
          проверить(бот[0].текст === 'играет бот', п + '[бот] слова «играет бот» (вышло: «' + бот[0].текст + '»)');
          проверить(бот[0].внутри && !бот[0].срезан, п + '[бот] «играет бот» целиком внутри карточки и не обрезано (внутри: ' + бот[0].внутри + ', обрезано: ' + бот[0].срезан + ')');
        }
      }
    } else {
      проверить(спящие.length === 0, п + '[бот] спящих нет, пометки «играет бот» нет (найдено: ' + спящие.length + ')');
    }
  }
  проверить(р.ошибки.length === 0, п + 'ошибок в консоли нет' + (р.ошибки.length ? ': ' + р.ошибки.join(' | ') : ''));
}

