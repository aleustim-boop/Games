/** В СТРАНИЦЕ: все замеры за один раз. */
function замерить() {
  const W = document.documentElement.clientWidth, H = window.innerHeight;
  const прям = function (р) { return { x: р.left, y: р.top, r: р.right, b: р.bottom, w: р.width, h: р.height }; };
  const видно = function (у) {
    if (!у) return false;
    const с = getComputedStyle(у), р = у.getBoundingClientRect();
    return с.display !== 'none' && с.visibility !== 'hidden' && р.width > 0 && р.height > 0 && !у.closest('.скрыт') && !у.closest('[hidden]');
  };
  const сверху = function (у) {
    const стар = у.style.pointerEvents; у.style.pointerEvents = 'auto';
    const р = у.getBoundingClientRect();
    const ц = document.elementFromPoint((р.left + р.right) / 2, (р.top + р.bottom) / 2);
    у.style.pointerEvents = стар;
    return Boolean(ц && (ц === у || у.contains(ц)));
  };
  const срезан = function (у) { return у.scrollWidth > у.clientWidth + 1 || у.scrollHeight > у.clientHeight + 3; };
  const итог = { W: W, H: H, вбок: document.documentElement.scrollWidth - W, узлы: {} };

  ['деберц-отсчёт', 'деберц-показ-отсчёт', 'деберц-итог-отсчёт'].forEach(function (id) {
    const у = document.getElementById(id);
    if (!у) { итог.узлы[id] = { есть: false }; return; }
    const з = { есть: true, виден: видно(у), текст: у.textContent, классы: у.className };
    const р = у.getBoundingClientRect();
    Object.assign(з, прям(р));
    з.вЭкране = р.left >= -0.5 && р.top >= -0.5 && р.right <= W + 0.5 && р.bottom <= H + 0.5;
    з.сверху = з.виден && сверху(у);
    const ц = document.elementFromPoint((р.left + р.right) / 2, (р.top + р.bottom) / 2);
    з.чтоСверху = ц ? (ц.id || String(ц.className) || ц.tagName) + ' <' + ц.tagName.toLowerCase() + '>' : 'ничего';
    з.срезан = срезан(у);
    // Сколько строк занимает текст: «с» на своей строке даст больше одной.
    const диап = document.createRange(); диап.selectNodeContents(у);
    const строки = new Set(Array.from(диап.getClientRects()).map(function (к) { return Math.round(к.top); }));
    з.строк = строки.size;
    const уз = у.firstChild;
    if (уз && уз.nodeType === 3) {
      const т = уз.textContent, иС = т.lastIndexOf('с');
      let иЧ = иС - 1;
      while (иЧ >= 0 && !/[0-9]/.test(т[иЧ])) иЧ--;
      if (иС > 0 && иЧ >= 0) {
        const верх = function (и) { const д = document.createRange(); д.setStart(уз, и); д.setEnd(уз, и + 1); return д.getBoundingClientRect().top; };
        з.верхЧисла = верх(иЧ); з.верхС = верх(иС);
      }
    }
    итог.узлы[id] = з;
  });
  итог.виднылиОтсчёты = Array.from(document.querySelectorAll('.деберц-отсчёт, .деберц-итог-отсчёт')).filter(видно).map(function (у) { return (у.id || у.className) + ': «' + у.textContent + '»'; });

  const плашка = document.getElementById('подсказка');
  итог.плашка = плашка ? { есть: true, виден: видно(плашка), классы: плашка.className, ...прям(плашка.getBoundingClientRect()) } : { есть: false };
  const чей = document.getElementById('деберц-чей-ход');
  if (чей && видно(чей)) {
    const диап = document.createRange(); диап.selectNodeContents(чей);
    итог.чейХод = { текст: чей.textContent.trim(), ...прям(диап.getBoundingClientRect()) };
  }
  const статус = document.getElementById('деберц-статус');
  if (статус && видно(статус)) {
    const диап = document.createRange(); диап.selectNodeContents(статус);
    итог.статусСлова = прям(диап.getBoundingClientRect());
  }
  итог.статус = статус ? { есть: true, виден: видно(статус), текст: статус.textContent.trim(), срезан: срезан(статус), ...прям(статус.getBoundingClientRect()) } : { есть: false };

  итог.карточки = Array.from(document.querySelectorAll('#деберц-участники .деберц-участник')).map(function (к) {
    const р = к.getBoundingClientRect();
    // Спрятанные по задумке подписи (роль на узком экране: display none) не считаем — мерим то, что видно.
    const дети = Array.from(к.children).filter(function (д) { return видно(д); }).map(function (д) {
      const рд = д.getBoundingClientRect();
      return { тег: д.tagName.toLowerCase(), класс: д.className, текст: д.textContent.trim(), срезан: срезан(д), р: прям(рд),
        внутри: рд.left >= р.left - 0.5 && рд.right <= р.right + 0.5 && рд.top >= р.top - 0.5 && рд.bottom <= р.bottom + 0.5 };
    });
    return { спит: к.classList.contains('деберц-участник--спит'), виден: видно(к), ...прям(р), дети: дети,
      вЭкране: р.left >= -0.5 && р.top >= -0.5 && р.right <= W + 0.5 && р.bottom <= H + 0.5 };
  });

  const действия = document.getElementById('деберц-итог-действия');
  итог.итогДействия = Array.from(действия ? действия.querySelectorAll('button') : []).filter(видно).map(function (б) {
    const р = б.getBoundingClientRect();
    return { текст: б.textContent.trim(), вЭкране: р.left >= -0.5 && р.top >= -0.5 && р.right <= W + 0.5 && р.bottom <= H + 0.5, сверху: сверху(б) };
  });
  return итог;
}

