/* =====================================================================
   СТРАЖ: ПОЛОВИНА ОЧКОВ НАПАРНИКА — ЦЕЛОЕ ЧИСЛО, БЕЗ ДРОБИ

   Что проверяем. В server/рейтинг.js, в учестьПартию (строки около
   966-986), при ничьей парами напарник получает половину обычной
   прибавки: «цена = ценаСоперника(другой, исход) * 0.5». Если цену не
   округлять, при нечётной цене (ничья с человеком = 5) выходит дробь —
   2,5 очка, и итог у игрока тоже дробный (12,5). Дробь в очках рейтинга
   игрок не поймёт: экран рисует счёт как целое число.

   Правильно: половина округляется ВНИЗ (Math.floor), и в счёт не может
   попасть дробь — ни у кого, ни разу.

   ВНИМАНИЕ ШТАБУ: в tests/очки-рейтинга-напарник.js (строки 91, 99-102,
   126, 130, 141) есть проверка, которая ждёт РОВНО 12.5 — дробное число.
   Эта проверка написана для прежнего поведения (без округления) и после
   починки округления вниз должна стать красной сама по себе (12 вместо
   12.5). Сам файл не трогаю — это старый образец, штаб решает, что с ним
   делать (обновить ожидание или снять).

   Как проверяем.
     1) Базовая цена одной ничьей с живым человеком без напарника —
        меряем прогоном 1×1 (число не захардкожено, чтобы страж не врал,
        если владелец однажды передвинет цену в таблице).
     2) Партия 2 на 2, все вничью (как в старом образце: 201-204): у
        каждого игрока прибавка = 2 обычных соперника (целые числа) +
        напарник (округлённая вниз половина базовой цены). Проверяем
        Number.isInteger у итоговых очков КАЖДОГО игрока, и что прибавка
        именно за напарника равна Math.floor(база / 2) — не база/2 и не
        Math.round.
     3) Повтор сценария «победитель + напарник-ничейник» и «ничейник
        против выигравшей пары» (как в старом образце, сценарии 4 и 5) —
        тоже целые числа у всех.
     4) Обычная партия 1×1 без поля «напарник» — цена не меняется и
        остаётся целой (совместимость с прежним поведением).

   Как устроен ломающий запуск. Функция учестьПартию берёт зависимости
   относительными require (./сила-игроков.js, ./папка-данных.js,
   ./игры/умолчания.js), поэтому испорченную копию нельзя просто положить
   одним файлом — нужно скопировать всю папку server/ и внутри копии
   убрать Math.floor. Довод скрипту — путь до рейтинг.js ВНУТРИ такой
   копии.

   Запуск (файл проекта):
     node tests/рейтинг-очки-напарника-целые.js

   Ломающий запуск:
     node tests/рейтинг-очки-напарника-целые.js ПУТЬ_К_РЕЙТИНГУ_В_КОПИИ_ПАПКИ_SERVER
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

process.env.GAMES_DATA = fs.mkdtempSync(path.join(os.tmpdir(), 'рейтинг-очки-напарника-целые-'));

const КОРЕНЬ = path.join(__dirname, '..');
const путьДовод = process.argv[2];
const ПУТЬ_РЕЙТИНГА = путьДовод ? path.resolve(путьДовод) : path.join(КОРЕНЬ, 'server', 'рейтинг.js');
const этоЛомающийЗапуск = Boolean(путьДовод);

console.log('=== Страж: половина очков напарника при ничьей — целая, без дроби ===');
console.log('Файл: ' + ПУТЬ_РЕЙТИНГА + (этоЛомающийЗапуск ? ' (ломающий запуск, копия)' : ' (файл проекта)'));
console.log('');

if (!fs.existsSync(ПУТЬ_РЕЙТИНГА)) {
  console.log('ПЛОХО — файл не найден вовсе: ' + ПУТЬ_РЕЙТИНГА);
  console.log('');
  console.log('Итого проверок: 1, провалов: 1');
  process.exit(1);
}

let рейтинг;
try {
  рейтинг = require(ПУТЬ_РЕЙТИНГА);
} catch (ошибка) {
  console.log('ПЛОХО — модуль не подключился: ' + ошибка.message);
  console.log('');
  console.log('Итого проверок: 1, провалов: 1');
  process.exit(1);
}

let ошибок = 0;
let проверок = 0;

function равно(что, было, надо) {
  проверок++;
  const ок = было === надо;
  if (!ок) ошибок++;
  console.log((ок ? 'ок' : 'ПЛОХО') + ' — ' + что + ': ' + было + (ок ? '' : ' (ждали ' + надо + ')'));
}

function целое(что, значение) {
  проверок++;
  const ок = Number.isInteger(значение);
  if (!ок) ошибок++;
  console.log((ок ? 'ок' : 'ПЛОХО') + ' — ' + что + ' целое число: ' + значение + (ок ? '' : ' — это ДРОБЬ, а не должно быть'));
}

/** Живой игрок за столом. Исход — 'победа', 'ничья' или 'поражение'. */
function человек(номер, исход, напарник) {
  return {
    номер: номер, имя: 'Т' + номер, этоБот: false,
    победил: исход === 'победа', ничья: исход === 'ничья',
    напарник: напарник === undefined ? null : напарник
  };
}

/** Сколько очков у игрока в этой игре сейчас. */
function очки(номер, игра) {
  const срез = рейтинг.срезДляИгрока(игра || 'дурак', номер);
  return срез.я ? срез.я.очки : 0;
}

/* --- 1. Базовая цена одной ничьей с человеком, без напарника --- */
console.log('1. База: 1×1, оба вничью — сколько даёт одна ничья с человеком без напарника');
рейтинг.забытьВсё();
рейтинг.учестьПартию('дурак', [
  человек(901, 'ничья'),
  человек(902, 'ничья')
]);
const БАЗА = очки(901);
целое('база ничьей (901)', БАЗА);
console.log('   база = ' + БАЗА + ' (используем дальше как мерку, число не захардкожено)');

/* --- 2. Партия 2 на 2, все вничью (тот же состав, что в старом образце) --- */
console.log('\n2. Партия 2 на 2: все четверо вничью (201-204, напарники 201↔203, 202↔204)');
рейтинг.забытьВсё();
рейтинг.учестьПартию('дурак', [
  человек(201, 'ничья', 203),
  человек(202, 'ничья', 204),
  человек(203, 'ничья', 201),
  человек(204, 'ничья', 202)
]);
const ОЖИДАЕМАЯ_ПРИБАВКА_НАПАРНИКА = Math.floor(БАЗА / 2);
const ожидаемыйИтог = БАЗА * 2 + ОЖИДАЕМАЯ_ПРИБАВКА_НАПАРНИКА;
for (const номер of [201, 202, 203, 204]) {
  целое('игрок ' + номер + ' (ничья с напарником)', очки(номер));
  равно('игрок ' + номер + ': итог целыми числами (не дробь вроде ' + (БАЗА * 2 + БАЗА / 2) + ')', очки(номер), ожидаемыйИтог);
}
/* Явно изолируем вклад именно напарника: итог минус два обычных соперника
   должен быть Math.floor(половины), а не половина как есть. */
равно('прибавка ИМЕННО за напарника равна Math.floor(база/2), не база/2', очки(201) - БАЗА * 2, ОЖИДАЕМАЯ_ПРИБАВКА_НАПАРНИКА);

/* --- 3. Смешанный сценарий: победитель с напарником-ничейником (как в старом образце, п.4) --- */
console.log('\n3. Партия 2 на 2: 401 победил, 402 проиграл, 403/404 — ничейники-напарники');
рейтинг.забытьВсё();
рейтинг.учестьПартию('дурак', [
  человек(401, 'победа', 403),
  человек(402, 'поражение', 404),
  человек(403, 'ничья', 401),
  человек(404, 'ничья', 402)
]);
целое('401: победитель с напарником', очки(401));
целое('402: проигравший с напарником', очки(402));
целое('403: ничейник-напарник', очки(403));
целое('404: ничейник-напарник', очки(404));

/* --- 4. Ничейник против выигравшей пары (как в старом образце, п.5) --- */
console.log('\n4. Партия 2 на 2: 501/502 вничью, 503/504 — победили');
рейтинг.забытьВсё();
рейтинг.учестьПартию('дурак', [
  человек(501, 'ничья', 503),
  человек(502, 'ничья', 504),
  человек(503, 'победа', 501),
  человек(504, 'победа', 502)
]);
целое('501: ничейник против выигравшей пары', очки(501));
целое('503: победитель с напарником', очки(503));

/* --- 5. Обычная партия 1×1 без напарника — совместимость --- */
console.log('\n5. Обычная партия 1×1 без поля «напарник» — цена не должна меняться');
рейтинг.забытьВсё();
рейтинг.учестьПартию('дурак', [
  человек(301, 'победа'),
  человек(302, 'поражение')
]);
целое('победитель без напарника (301)', очки(301));
целое('проигравший без напарника (302)', очки(302));

console.log('\n----------------------------------------');
console.log('Итого проверок: ' + проверок + ', провалов: ' + ошибок);
process.exit(ошибок ? 1 : 0);
