'use strict';

/* =====================================================================
   СТРАЖ: ОЧКИ РЕЙТИНГА В ИГРЕ 2 НА 2 — ТОЛЬКО ЦЕЛЫЕ, ПОЛОВИН НЕТ

   Что проверяем. Решение владельца 30.09 09:31: за напарника 0 очков
   (раньше давали половину цены, и при нечётной цене вылезала дробь
   вроде 12,5). Само «за напарника 0» слово в слово проверяет
   tests/очки-рейтинга-напарник.js — здесь это не повторяется.

   Здесь стережём другое: у КАЖДОГО игрока в игре пара на пару очки —
   целое число, всегда. Дробь игрок не поймёт (экран рисует счёт целым),
   а вернуться она может по любой из дорог: кто-то снова введёт долю за
   напарника, коэффициент за сложного бота, «половину за ничью» и т.п.

   Как проверяем (прогоном всех сочетаний, без выборочных примеров):
     - пара из двух живых напарников против пары соперников; соперник —
       живой человек или бот (лёгкий, обычный, сложный) — все 10 сочетаний
       двух соперников, включая смесь «человек + бот»;
     - исходы четверых — все 3 в 4-й степени = 81 вариант (победа, ничья,
       поражение; в том числе РАЗНЫЙ исход внутри пары);
     - на каждой партии: целые и неотрицательные и то, что вернула
       учестьПартию, и то, что видно в срезе игрока (итог очков);
     - вторая партия подряд у тех же людей: накопленный итог тоже целый;
     - контроль: партия 1×1 без напарника тоже целая (совместимость).
   Порог: если проверок выполнилось меньше ожидаемого — краснеем
   (ноль найденного — провал, а не пропуск).

   УМЕЕТ КРАСНЕТЬ:
     node tests/рейтинг-очки-напарника-целые.js --сломать [папка]
   копирует server/ (без server/данные) и общее/js/игры-реестр.js во временную
   папку системы (os.tmpdir(); необязательная «папка» — только имя
   подпапки-метки, проект не трогается), в КОПИИ server/рейтинг.js вместо
   пропуска напарника возвращает «половину цены без округления» и гоняет
   те же проверки на копии — обязан покраснеть. Не нашлось место порчи
   в копии — тоже провал, громко.

   Запуск: node tests/рейтинг-очки-напарника-целые.js
   Выход 0 — провалов нет.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const гдеЛомать = process.argv.indexOf('--сломать');
const ЛОМАТЬ = гдеЛомать !== -1;

let проверок = 0;
let ошибок = 0;
let показаноПровалов = 0;

function целое(что, значение) {
  проверок++;
  const ок = Number.isInteger(значение) && значение >= 0;
  if (ок) return;
  ошибок++;
  if (показаноПровалов++ < 12) {
    console.log('ПЛОХО — ' + что + ': ' + значение + ' (ждали целое неотрицательное число)');
  }
}

function громкийПровал(текст) {
  console.log('ПЛОХО — ' + текст);
  console.log('');
  console.log('Итого проверок: ' + проверок + ', провалов: ' + (ошибок + 1));
  process.exit(1);
}

/** Заменить ровно одно вхождение, иначе приём порчи устарел — сказать вслух. */
function заменитьРовноОдин(файл, старое, новое) {
  const части = fs.readFileSync(файл, 'utf8').split(старое);
  if (части.length !== 2) {
    громкийПровал('место порчи в копии не нашлось: «' + старое + '» встречается ' +
      (части.length - 1) + ' раз(а) вместо одного — поправьте проверку тем же коммитом');
  }
  fs.writeFileSync(файл, части.join(новое), 'utf8');
}

/* Порча: напарник снова приносит половину цены, БЕЗ округления. */
const ПОРЧА =
  'if (этоНапарник) {\n' +
  '        /* ИСПОРЧЕНО --сломать: половина цены за напарника, без округления */\n' +
  "        const заНапарника = начислить(запись, 'человек', ценаСоперника(другой, исход) * 0.5, сегодня);\n" +
  '        добавлено[игрок.номер] += заНапарника;\n' +
  '        if (половина) половина.очки += заНапарника;\n' +
  '        половинаСостава.очки += заНапарника;\n' +
  '        continue;\n' +
  '      }';

function кодИзКопииИлиПроекта() {
  if (!ЛОМАТЬ) return КОРЕНЬ;
  const метка = process.argv[гдеЛомать + 1];
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'очки-напарника-целые-' +
    (метка && метка.indexOf('--') !== 0 ? path.basename(метка) + '-' : '')));
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(папка, 'server'), {
    recursive: true,
    filter: function (откуда) {
      const имя = path.basename(откуда);
      return имя !== 'данные' && имя !== 'node_modules';
    }
  });
  require('./пути-проекта.js').создатьПапкиКода(папка);
  fs.copyFileSync(path.join(КОРЕНЬ, 'общее', 'js', 'игры-реестр.js'), path.join(папка, 'общее', 'js', 'игры-реестр.js'));
  заменитьРовноОдин(path.join(папка, 'server', 'рейтинг.js'), 'if (этоНапарник) continue;', ПОРЧА);
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: код из испорченной копии ' + папка + ' — прогон обязан провалиться ***\n');
  return папка;
}

const КОД = кодИзКопииИлиПроекта();
process.env.GAMES_DATA = fs.mkdtempSync(path.join(os.tmpdir(), 'очки-напарника-целые-данные-'));
const рейтинг = require(path.join(КОД, 'server', 'рейтинг.js'));

console.log('=== Страж: очки в игре 2 на 2 — только целые, половин нет ===\n');

const ИСХОДЫ = ['победа', 'ничья', 'поражение'];
const ВИДЫ_СОПЕРНИКА = ['человек', 'лёгкий', 'обычный', 'сложный'];

function человек(номер, исход, напарник) {
  return {
    номер: номер, имя: 'Т' + номер, этоБот: false,
    победил: исход === 'победа', ничья: исход === 'ничья',
    напарник: напарник === undefined ? null : напарник
  };
}
function бот(уровень, исход) {
  return { этоБот: true, уровень: уровень, победил: исход === 'победа', ничья: исход === 'ничья' };
}
function соперник(вид, исход, номер, напарник) {
  return вид === 'человек' ? человек(номер, исход, напарник) : бот(вид, исход);
}
function очки(номер) {
  const срез = рейтинг.срезДляИгрока('дурак', номер);
  return срез.я ? срез.я.очки : 0;
}

/* Все сочетания двух соперников (с повтором видов), все исходы четверых. */
let партий = 0;
let номерПартии = 0;
for (let а = 0; а < ВИДЫ_СОПЕРНИКА.length; а++) {
  for (let б = а; б < ВИДЫ_СОПЕРНИКА.length; б++) {
    const виды = [ВИДЫ_СОПЕРНИКА[а], ВИДЫ_СОПЕРНИКА[б]];
    for (const и1 of ИСХОДЫ) for (const и2 of ИСХОДЫ) for (const и3 of ИСХОДЫ) for (const и4 of ИСХОДЫ) {
      рейтинг.забытьВсё();
      партий++;
      номерПартии++;
      // Номера новые на каждую партию — упирается только правило очков.
      const н = 1000 + номерПартии * 10;
      const подпись = виды.join('+') + ' исходы ' + [и1, и2, и3, и4].join('/');
      const состав = [
        человек(н + 1, и1, н + 3),
        соперник(виды[0], и2, н + 2, н + 4),
        человек(н + 3, и3, н + 1),
        соперник(виды[1], и4, н + 4, н + 2)
      ];
      for (let раз = 1; раз <= 2; раз++) {
        const добавлено = рейтинг.учестьПартию('дурак', состав);
        for (const номер of [н + 1, н + 3]) {
          целое('партия ' + раз + ', ' + подпись + ', игрок ' + номер + ': добавлено', добавлено[номер]);
          целое('партия ' + раз + ', ' + подпись + ', игрок ' + номер + ': итог', очки(номер));
        }
        for (const [номер, вид] of [[н + 2, виды[0]], [н + 4, виды[1]]]) {
          if (вид !== 'человек') continue;
          целое('партия ' + раз + ', ' + подпись + ', живой соперник ' + номер + ': итог', очки(номер));
        }
      }
    }
  }
}

/* Контроль: обычная партия 1×1 без напарника. */
for (const и1 of ИСХОДЫ) for (const и2 of ИСХОДЫ) {
  рейтинг.забытьВсё();
  const добавлено = рейтинг.учестьПартию('дурак', [человек(9001, и1), человек(9002, и2)]);
  целое('1×1 ' + и1 + '/' + и2 + ': игрок 9001', добавлено[9001]);
  целое('1×1 ' + и1 + '/' + и2 + ': игрок 9002', очки(9002));
}

/* Порог: 10 сочетаний × 81 исход × 2 партии, минимум по 2 проверки на человека. */
const ОЖИДАЕМО_МИНИМУМ = 3000;
console.log('Сыграно партий 2 на 2: ' + партий + ' (ждали 810)');
if (партий !== 810) громкийПровал('партий сыграно ' + партий + ' вместо 810');
if (проверок < ОЖИДАЕМО_МИНИМУМ) {
  громкийПровал('выполнено проверок ' + проверок + ' — меньше порога ' + ОЖИДАЕМО_МИНИМУМ + ' (ноль найденного — провал)');
}
if (показаноПровалов > 12) console.log('... и ещё ' + (показаноПровалов - 12) + ' провалов (показаны первые 12)');

console.log('\n----------------------------------------');
console.log('Итого проверок: ' + проверок + ', провалов: ' + ошибок);
process.exit(ошибок ? 1 : 0);
