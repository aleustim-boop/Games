/** Все rgb()/rgba() внутри строки — фон бывает многослойным (градиенты). */
function всеRgba(строка) {
  const рез = [];
  const рег = /rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)(?:\s*,\s*([\d.]+))?\s*\)/g;
  let м;
  while ((м = рег.exec(строка || ''))) {
    рез.push({ r: Number(м[1]), g: Number(м[2]), b: Number(м[3]), a: м[4] === undefined ? 1 : parseFloat(м[4]) });
  }
  return рез;
}
function разобратьRgba(строка) { return всеRgba(строка)[0] || null; }
function бордовый(ц) { return (ц.r - Math.max(ц.g, ц.b)) >= 20; }
function яркость(ц) { return (ц.r + ц.g + ц.b) / 3; }

const провалыЦвета = [];
let проверокЦвета = 0;

/** Служебный экран должен быть тёмным графитом сборника, не бордовым и
    не прозрачным (прозрачность — тоже поломка: значит своего фона нет). */
async function проверитьЭкранТёмный(страница, id, метка) {
  проверокЦвета++;
  const данные = await страница.evaluate(function (и) {
    const у = document.getElementById(и);
    return у ? { backgroundColor: getComputedStyle(у).backgroundColor } : null;
  }, id);
  if (!данные) { провалыЦвета.push(метка + ': узел #' + id + ' не найден'); return; }
  const ц = разобратьRgba(данные.backgroundColor);
  if (!ц || ц.a < 0.5) {
    провалыЦвета.push(метка + ': фон прозрачный или не разобрать (' + данные.backgroundColor + ') — сплошного тёмного фона нет');
  } else if (бордовый(ц)) {
    провалыЦвета.push(метка + ': фон бордовый вместо тёмного графита (rgb ' + ц.r + ',' + ц.g + ',' + ц.b + ')');
  } else if (яркость(ц) >= 60) {
    провалыЦвета.push(метка + ': фон слишком светлый (яркость ' + яркость(ц).toFixed(1) + ', rgb ' + ц.r + ',' + ц.g + ',' + ц.b + ')');
  } else {
    console.log('    цвет ок: ' + метка + ' тёмный, не бордовый (rgb ' + ц.r + ',' + ц.g + ',' + ц.b + ')');
  }
}

/** Стол партии должен быть заметно бордовым — сукно. */
async function проверитьСтолБордовый(страница) {
  проверокЦвета++;
  const данные = await страница.evaluate(function () {
    const у = document.getElementById('зона-стола');
    return у ? { backgroundImage: getComputedStyle(у).backgroundImage } : null;
  });
  if (!данные) { провалыЦвета.push('стол партии: узел #зона-стола не найден'); return; }
  const цвета = всеRgba(данные.backgroundImage);
  if (!цвета.some(бордовый)) {
    провалыЦвета.push('стол партии: в фоне #зона-стола нет бордового оттенка сукна (нашли: ' +
      цвета.map(function (ц) { return ц.r + ',' + ц.g + ',' + ц.b; }).join(' | ') + ')');
  } else {
    console.log('    цвет ок: сукно стола бордовое');
  }
}

/** Скопировать проект в временную папку для ломающего запуска. */
