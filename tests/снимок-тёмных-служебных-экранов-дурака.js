/** Испортить CSS в копии: служебные экраны — светлые вместо тёмных. */
function сломатьСлужебныеЭкраныВКопии(tmp) {
  const файл = path.join(tmp, 'style.css');
  const исходный = fs.readFileSync(файл, 'utf-8');
  // Заменяем переменную --сб-фон (тёмный графит служебных экранов) на светлый серый
  let испорченный = исходный.replace(/--сб-фон:\s*[^;]+;/, '--сб-фон: rgb(200, 200, 200);');
  if (исходный === испорченный) {
    throw new Error('испортитель цвета экранов не нашёл --сб-фон в style.css — правило уехало');
  }
  fs.writeFileSync(файл, испорченный, 'utf-8');
  return файл;
}

/** Испортить CSS в копии: сукно стола — без бордового оттенка (делаем зелёным). */
function сломатьСукноСтолаВКопии(tmp) {
  const файл = path.join(tmp, 'style.css');
  const исходный = fs.readFileSync(файл, 'utf-8');
  // Ищем бордовый цвет в фоне #зона-стола и меняем его на зелёный
  let испорченный = исходный.replace(/#900020/g, '#009000');
  if (исходный === испорченный) {
    throw new Error('испортитель сукна не нашёл #900020 в style.css — бордовый цвет уехал');
  }
  fs.writeFileSync(файл, испорченный, 'utf-8');
  return файл;
}

