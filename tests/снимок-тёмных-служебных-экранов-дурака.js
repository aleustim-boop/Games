'use strict';

/* =====================================================================
   СНИМКИ ТРЁХ СЛУЖЕБНЫХ ЭКРАНОВ «ИГРЫ С ДРУГОМ» ПОСЛЕ ТЁМНОЙ ПАЛИТРЫ.

   Зачем. Оформитель покрасил #экран-друга, #экран-комнаты и #экран-входа
   в тёмный (style.css, ~4439: переменные --сб-*), чтобы сквозь них не
   просвечивало сукно стола. Нужны снимки для смотрителя — оценить,
   стало ли лучше. Вид экранов (цвета, отступы) скрипт не проверяет —
   это дело смотрителя по снимку. А вот что экран дошёл (появился,
   получил класс «экран--виден») и что дорога до него не намусорила
   в консоли — проверяет по-настоящему: не дошёл или намусорил —
   стенд падает с кодом 1 (см. «беды»/«красные» ниже).

   ВАЖНО (проверено чтением js/сеть.js, js/открытые-столы.js,
   js/дурак-путь.js, js/game.js): с переездом на новое лобби (три входа)
   старая карточка «лобби-друзья» больше НЕ ведёт на #экран-друга — она
   зовёт window.Сеть.пригласитьВПриложение() (шеринг ссылки). #экран-друга
   теперь показывается только как ЗАПАСНОЙ экран, когда создание комнаты
   не удалось (сервер недоступен) — «наЭкранДругаСБедой» в js/сеть.js.
   Поэтому дорога у стенда в два захода:

   Заход 1 (адрес сервера заведомо недоступен — порт, на котором никто
   не слушает): витрина → «Дурак» → лобби → «Играть онлайн»
   (#лобби-играть-онлайн) → «Создать игру» (#открытые-столы-создать) →
   три шага (правила → игроки → настройки) → «Создать игру» (#путь-начать)
   → сервер не ответил → запасной «Игра с другом» (#экран-друга) с бедой.

   Заход 2 (адрес — настоящий рабочий сервер комнат): та же дорога →
   на этот раз комната создаётся по-настоящему → #экран-комнаты. «Выйти
   из комнаты» → лобби → «Играть онлайн» → «Есть код? Войти»
   (#открытые-столы-код, кликает скрытую #кнопка-войти-по-коду) →
   #экран-входа — этот вход в сеть вообще не стучится, экран открывается
   всегда.

   Запуск:
       node tests/снимок-тёмных-служебных-экранов-дурака.js
   Сервер страниц поднимает сам (tests/локальный-сервер.js) на порту 8081
   (если занят — берёт случайный свободный), сервер комнат — свою копию
   server/сервер.js «--без-памяти» на случайном свободном порту (не 8790!).
   Оба гасит за собой и печатает, что порты после этого молчат.
   ===================================================================== */

const http = require('http');
const net = require('net');
const fs = require('fs');
const path = require('path');
const { spawn } = require('child_process');
const { chromium, подготовитьПодделку } = require('./браузер-робот.js');

const ПАПКА_ПРОЕКТА = path.join(__dirname, '..');
const ПАПКА_СНИМКОВ = path.join(__dirname, 'снимки');
const ПРЕДПОЧТИТЕЛЬНЫЙ_ПОРТ_СТРАНИЦ = 8081;

const спать = (мс) => new Promise((р) => setTimeout(р, мс));

function портСвободен(порт) {
  return new Promise((готово) => {
    const проба = net.createServer();
    проба.once('error', () => готово(false));
    проба.listen(порт, '127.0.0.1', () => проба.close(() => готово(true)));
  });
}

function свободныйПорт() {
  return new Promise((готово) => {
    const проба = net.createServer();
    проба.listen(0, '127.0.0.1', () => {
      const порт = проба.address().port;
      проба.close(() => готово(порт));
    });
  });
}

function постучать(адрес) {
  return new Promise((готово) => {
    const запрос = http.get(адрес, (ответ) => { ответ.resume(); готово(true); });
    запрос.on('error', () => готово(false));
    запрос.setTimeout(2000, () => { запрос.destroy(); готово(false); });
  });
}

async function ждатьОтвета(адрес, максМс) {
  const край = Date.now() + (максМс || 8000);
  while (Date.now() < край) {
    if (await постучать(адрес)) return true;
    await спать(150);
  }
  return false;
}

async function ждатьМолчания(адрес, максМс) {
  const край = Date.now() + (максМс || 5000);
  while (Date.now() < край) {
    if (!(await постучать(адрес))) return true;
    await спать(150);
  }
  return false;
}

function поднятьПроцесс(команда, аргументы, метка) {
  return new Promise((resolve, reject) => {
    const процесс = spawn(команда, аргументы, { cwd: ПАПКА_ПРОЕКТА, stdio: ['ignore', 'pipe', 'pipe'] });
    процесс.stdout.on('data', (д) => console.log('[' + метка + '] ' + д.toString().trim()));
    процесс.stderr.on('data', (д) => console.error('[' + метка + ' ошибка] ' + д.toString().trim()));
    процесс.on('error', reject);
    setTimeout(() => resolve(процесс), 400);
  });
}

async function ждатьВидимогоЭкрана(страница, id, максМс) {
  try {
    await страница.waitForFunction((и) => {
      const узел = document.getElementById(и);
      return Boolean(узел && узел.classList.contains('экран--виден'));
    }, id, { timeout: максМс || 8000 });
    return true;
  } catch (ошибка) {
    const видно = await страница.evaluate(() => {
      const э = document.querySelector('.экран.экран--виден');
      return э ? э.id : '(нет видимого экрана)';
    });
    console.error('    не дождался экрана «' + id + '», сейчас видно: ' + видно);
    return false;
  }
}

async function нажать(страница, селектор, что) {
  await страница.waitForSelector(селектор, { state: 'visible', timeout: 8000 });
  await страница.click(селектор, { timeout: 5000 });
  console.log('    нажал: ' + что);
}

/** Дурак → лобби → «Играть онлайн» → экран «Играть онлайн» построен. */
async function дойтиДоЛоббиИОнлайна(страница) {
  await нажать(страница, '#кнопка-игра-дурак', 'Дурак на витрине');
  await ждатьВидимогоЭкрана(страница, 'экран-лобби', 8000);
  await спать(200);
  await нажать(страница, '#лобби-играть-онлайн', '«Играть онлайн» в лобби');
  await ждатьВидимогоЭкрана(страница, 'экран-открытые-столы', 8000);
  await спать(200);
}

/** «Создать игру» с экрана «Играть онлайн» → три шага → «Создать игру» в конце. */
async function пройтиТриШагаИСоздать(страница) {
  await нажать(страница, '#открытые-столы-создать', '«Создать игру» на экране «Играть онлайн»');
  await ждатьВидимогоЭкрана(страница, 'экран-путь-правила', 8000);
  await спать(150);
  await нажать(страница, '.экран.экран--виден [data-путь="далее"]', 'Далее на шаге 1 «Правила»');
  await ждатьВидимогоЭкрана(страница, 'экран-путь-игроки', 8000);
  await спать(150);
  await нажать(страница, '.экран.экран--виден [data-путь="далее"]', 'Далее на шаге 2 «Игроки»');
  await ждатьВидимогоЭкрана(страница, 'экран-путь-настройки', 8000);
  await спать(150);
  await нажать(страница, '#путь-начать', '«Создать игру» на шаге 3 «Настройки»');
}

async function запустить() {
  console.log('Снимки тёмных служебных экранов дурака (друг / комната / вход по коду)');

  if (!fs.existsSync(ПАПКА_СНИМКОВ)) fs.mkdirSync(ПАПКА_СНИМКОВ, { recursive: true });

  const портСтраниц = (await портСвободен(ПРЕДПОЧТИТЕЛЬНЫЙ_ПОРТ_СТРАНИЦ)) ? ПРЕДПОЧТИТЕЛЬНЫЙ_ПОРТ_СТРАНИЦ : await свободныйПорт();
  const портКомнат = await свободныйПорт();
  const портБеды = await свободныйПорт();   // на нём сознательно НИЧЕГО не поднимаем — «сервер недоступен»
  console.log('Порт страниц: ' + портСтраниц + ', порт рабочих комнат: ' + портКомнат + ', порт беды (пустой): ' + портБеды);

  let процессСтраниц = null;
  let процессКомнат = null;
  let браузер = null;
  const снятыеСнимки = [];
  const красные = [];
  const беды = [];

  try {
    процессСтраниц = await поднятьПроцесс('node', ['tests/локальный-сервер.js', String(портСтраниц)], 'страницы');
    const страницыЖивы = await ждатьОтвета('http://127.0.0.1:' + портСтраниц + '/index.html', 8000);
    if (!страницыЖивы) throw new Error('страничный сервер на ' + портСтраниц + ' не ответил');
    console.log('Страничный сервер живой ✓');

    процессКомнат = await поднятьПроцесс('node', ['server/сервер.js', String(портКомнат), '--без-памяти'], 'комнаты');
    const комнатыЖивы = await ждатьОтвета('http://127.0.0.1:' + портКомнат + '/здоровье', 10000);
    if (!комнатыЖивы) throw new Error('сервер комнат на ' + портКомнат + ' не ответил');
    console.log('Сервер комнат живой ✓');

    браузер = await chromium.launch();
    const контекст = await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
    const страница = await контекст.newPage();
    страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
    страница.on('console', (м) => {
      if (м.type() !== 'error') return;
      const текст = м.text();
      const л = м.location && м.location();
      const откуда = (л && л.url) || '';
      const вместе = текст + ' ' + откуда;
      /* ФИЛЬТР ОЖИДАЕМОГО ШУМА (проверено requestfailed-логом при разборе,
         почему стенд краснел на исправной игре):

         1. Настоящий telegram-web-app.js «браузер-робот.js» сознательно
            обрывает (route.abort), чтобы он не затёр подделку Telegram —
            Chromium сам пишет об этом отказе в консоль красным. Это след
            нашей же подделки, не поломка игры. Тот же приём — в
            tests/браузер-друзья-экран.js («следитьЗаКонсолью»).
         2. Заход 1 этого же стенда НАРОЧНО указывает адрес сервера на
            порт «беды» (портБеды), где сознательно никто не слушает —
            это и есть проверяемый сценарий («сервер недоступен» →
            запасной «Игра с другом»). Chromium пишет об отказе
            подключиться в консоль красным — это ожидаемое следствие
            сценария, не поломка. Один такой отказ долетает уже ПОСЛЕ
            перехода на заход 2 (фоновый опрос «здоровья» не успевает
            отмениться до смены страницы) — фильтруем по номеру порта,
            а не по номеру захода, чтобы поймать и этот хвост. Порт
            рабочего сервера (портКомнат) этим фильтром не защищён:
            сетевая ошибка на НЁМ была бы настоящей находкой. */
      if (/telegram-web-app\.js|telegram\.org/.test(вместе)) return;
      if (вместе.indexOf(':' + портБеды + '/') !== -1) return;
      красные.push('консоль: ' + текст + (откуда ? ' (' + откуда + ')' : ''));
    });

    await подготовитьПодделку(страница, { версия: '7.10' });

    /* ---------------- Заход 1: сервер недоступен → #экран-друга (беда) ---------------- */
    const адресБеды = 'http://127.0.0.1:' + портСтраниц + '/index.html?сервер=' + encodeURIComponent('http://127.0.0.1:' + портБеды);
    console.log('\nЗаход 1 (сервер недоступен): ' + адресБеды);
    await страница.goto(адресБеды, { waitUntil: 'domcontentloaded' });
    await дойтиДоЛоббиИОнлайна(страница);
    await пройтиТриШагаИСоздать(страница);
    const другВиден = await ждатьВидимогоЭкрана(страница, 'экран-друга', 10000);
    await спать(400);
    if (другВиден) {
      const файл1 = path.join(ПАПКА_СНИМКОВ, 'тёмный-экран-друга-390x844.png');
      await страница.screenshot({ path: файл1 });
      снятыеСнимки.push(файл1);
      console.log('Снимок: ' + файл1);
    } else {
      беды.push('экран-друга не появился после неудачного создания игры — снимок НЕ снят');
    }

    /* ---------------- Заход 2: рабочий сервер → #экран-комнаты и #экран-входа ---------------- */
    const адресРабочий = 'http://127.0.0.1:' + портСтраниц + '/index.html?сервер=' + encodeURIComponent('http://127.0.0.1:' + портКомнат);
    console.log('\nЗаход 2 (рабочий сервер): ' + адресРабочий);
    await страница.goto(адресРабочий, { waitUntil: 'domcontentloaded' });
    await дойтиДоЛоббиИОнлайна(страница);
    await пройтиТриШагаИСоздать(страница);
    const комнатаВидна = await ждатьВидимогоЭкрана(страница, 'экран-комнаты', 10000);
    await спать(500);
    if (комнатаВидна) {
      const файл2 = path.join(ПАПКА_СНИМКОВ, 'тёмный-экран-комнаты-390x844.png');
      await страница.screenshot({ path: файл2 });
      снятыеСнимки.push(файл2);
      console.log('Снимок: ' + файл2);
    } else {
      беды.push('экран-комнаты не появился при рабочем сервере — снимок НЕ снят');
    }

    if (комнатаВидна) {
      await нажать(страница, '#кнопка-комната-отмена', '«Выйти из комнаты»');
      await ждатьВидимогоЭкрана(страница, 'экран-лобби', 8000);
      await спать(200);
    } else {
      // Всё равно попробуем дойти до входа по коду с лобби напрямую.
      await страница.evaluate(() => { if (typeof показатьЛоббиДурака === 'function') показатьЛоббиДурака(); });
      await ждатьВидимогоЭкрана(страница, 'экран-лобби', 8000);
    }

    await нажать(страница, '#лобби-играть-онлайн', '«Играть онлайн» в лобби (второй раз)');
    await ждатьВидимогоЭкрана(страница, 'экран-открытые-столы', 8000);
    await спать(200);
    await нажать(страница, '#открытые-столы-код', '«Есть код? Войти»');
    const входВиден = await ждатьВидимогоЭкрана(страница, 'экран-входа', 8000);
    await спать(300);
    if (входВиден) {
      const файл3 = path.join(ПАПКА_СНИМКОВ, 'тёмный-экран-входа-390x844.png');
      await страница.screenshot({ path: файл3 });
      снятыеСнимки.push(файл3);
      console.log('Снимок: ' + файл3);
    } else {
      беды.push('экран-входа не появился — снимок НЕ снят');
    }

    if (красные.length) {
      console.log('\nВ консоли/при падениях страницы было ' + красные.length + ' строк:');
      красные.forEach((с) => console.log('  ' + с));
    } else {
      console.log('\nОшибок в консоли и падений: нет ✓');
    }

    await контекст.close();
    await браузер.close();
    браузер = null;
    console.log('Браузер закрыт ✓');
  } finally {
    if (браузер) { try { await браузер.close(); } catch (е) { /* уже закрыт */ } }
    if (процессКомнат && процессКомнат.pid) {
      console.log('Гашу сервер комнат (PID ' + процессКомнат.pid + ')...');
      процессКомнат.kill();
      const молчит = await ждатьМолчания('http://127.0.0.1:' + портКомнат + '/здоровье', 5000);
      console.log('Порт ' + портКомнат + ' (комнаты): ' + (молчит ? 'молчит ✓' : 'ВСЁ ЕЩЁ ОТВЕЧАЕТ — не погас!'));
    }
    if (процессСтраниц && процессСтраниц.pid) {
      console.log('Гашу страничный сервер (PID ' + процессСтраниц.pid + ')...');
      процессСтраниц.kill();
      const молчит = await ждатьМолчания('http://127.0.0.1:' + портСтраниц + '/index.html', 5000);
      console.log('Порт ' + портСтраниц + ' (страницы): ' + (молчит ? 'молчит ✓' : 'ВСЁ ЕЩЁ ОТВЕЧАЕТ — не погас!'));
    }
  }

  console.log('\nСнято снимков: ' + снятыеСнимки.length + ' из 3');
  снятыеСнимки.forEach((ф) => console.log('  ' + ф));
  if (беды.length) {
    console.log('\nНЕ УДАЛОСЬ:');
    беды.forEach((б) => console.log('  ' + б));
  }
  if (беды.length || красные.length) process.exit(1);
}

запустить().catch((ошибка) => {
  console.error('Стенд упал: ' + ошибка.message);
  console.error(ошибка.stack);
  process.exit(2);
});
