/* =====================================================================
   РЕЙТИНГ — ПОВТОРНАЯ ДОСТАВКА ПАРТИИ: одна партия начисляется один раз.

   Зачем эта проверка. До правки server/рейтинг.js.учестьПартию начисляло
   очки при КАЖДОМ вызове — партия не имела своего ключа. Комнаты держали
   в памяти пометку «партияУчтена», билет одноразов — это смягчало беду,
   но после перезапуска сервера комната теряет пометку из памяти (она
   только в оперативной памяти, не на диске), а билет уже погашен и
   удалён: второй вызов учестьПартию с тем же застольем ничем не
   отличался от первого, и очки задваивались.

   Теперь у партии есть необязательный третий довод — ключ. Знакомый
   ключ второй раз ничего не начисляет и отдаёт {}; новый ключ считается
   как обычно и запоминается (список + Set, потолок 5000, старые
   вытесняются первыми, ключи переживают перезапуск — лежат в том же
   файле рейтинга рядом с очками).

   ЧТО ПРОВЕРЯЕМ (память рейтинга — во временной папке, боевых данных
   владельца проверка не касается, приём — тот же, что в
   tests/очки-рейтинга.js):
     а) один и тот же ключ партии дважды — второй вызов отдаёт {},
        очки/партий/побед не растут, сила не пересчитывается;
     б) два РАЗНЫХ ключа — обе партии засчитаны;
     в) партия БЕЗ ключа (старые вызовы, старые проверки) — считается
        при каждом вызове, как было всегда, память защиты не растёт;
     г) ключ переживает записатьСейчас() (файл на диске) и новую
        загрузку — как будто сервер перезапустился;
     д) потолок памяти — 5000 ключей: 5001-й выталкивает самый старый,
        и тот, вытесненный, снова засчитывается, будто он новый;
        свежий ключ при этом остаётся в памяти и отсекает повтор;
     е) НАСТОЯЩАЯ комната: партия по-честному сыграна через HTTP-двери
        сервера комнат (/создать, /ход, /состояние — тот же протокол,
        что у браузера); настоящий ключ, которым server/комнаты.js
        зовёт рейтинг, подсмотрен без подмены логики (оригинал
        вызывается как обычно, доводы только записываются в сторонке).
        Повторная доставка того же ключа напрямую в рейтинг (эмуляция
        «сервер перезапустился, партияУчтена в памяти сброшена, а ключ
        на диске остался») — очков не добавляет. Реванш (вторая партия
        той же комнаты) получает СВОЙ ключ и засчитывается отдельно.

   УМЕЕТ ЛИ ОНА КРАСНЕТЬ. node tests/рейтинг-повтор-партии.js --сломать
   берёт временную КОПИЮ server/рейтинг.js (боевой файл не трогается),
   убирает из неё проверку «ключ уже учтён» и гоняет только случай (а) —
   он обязан провалиться: второй вызов с тем же ключом снова начислит
   очки.

   Запуск:
       node tests/рейтинг-повтор-партии.js             (обычный прогон)
       node tests/рейтинг-повтор-партии.js --сломать   (обязан провалиться)
   Выход 0 — провалов нет, 1 — провал (смотреть строки «ПРОВАЛ» в выводе).
   ===================================================================== */

