function вырезатьФункцию(исходный, имя) {
  const текст = исходный.split(String.fromCharCode(13)).join('');
  const начало = текст.indexOf('function ' + имя + '(');
  if (начало < 0) return '';
  const конец = текст.indexOf('\n  }\n', начало);
  return конец < 0 ? '' : текст.slice(начало, конец + 4);
}

function убратьКод(исходник, search, hash) {
  const текст = вырезатьФункцию(исходник, 'убратьКодИзАдреса');
  ждать(текст, 'п5: функция убратьКодИзАдреса не найдена (ноль найденного)');
  const журнал = [];
  const окно = {
    location: { pathname: '/домино.html', search, hash },
    history: { state: { s: 1 }, replaceState(состояние, заголовок, адрес) { журнал.push(адрес); } }
  };
  vm.runInNewContext(текст + '\nубратьКодИзАдреса();', { window: окно, decodeURIComponent, String });
  return журнал;
}

