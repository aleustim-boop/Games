// ---------------------------------------------------------------- поддельная страница для листа «⋯»
function поддельныйУзел(счёт) {
  const данные = { classList: { contains: () => false, add() {}, remove() {}, toggle() {} }, offsetParent: null, children: [], style: {}, dataset: {} };
  return new Proxy(function () {}, {
    get(цель, ключ) {
      if (ключ in данные) return данные[ключ];
      if (ключ === 'querySelector') return () => поддельныйУзел();
      if (ключ === 'querySelectorAll') return () => [];
      if (ключ === 'contains') return () => false;
      if (['addEventListener', 'appendChild', 'setAttribute', 'insertBefore', 'removeAttribute'].includes(ключ)) return () => {};
      if (ключ === Symbol.toPrimitive) return () => '';
      return данные[ключ];
    },
    set(цель, ключ, значение) { данные[ключ] = значение; return true; }
  });
}

function загрузитьЛист(файл) {
  const счёт = { кнопок: 0 };
  const лист = поддельныйУзел();
  const документ = {
    getElementById: () => лист, addEventListener() {}, querySelector: () => null,
    createElement(тег) { if (тег === 'button') счёт.кнопок++; return поддельныйУзел(); },
    body: поддельныйУзел(), documentElement: поддельныйУзел(), readyState: 'complete'
  };
  const окно = { document: документ, addEventListener() {} };
  const среда = { window: окно, document: документ, module: { exports: {} }, setTimeout, clearTimeout, setInterval, clearInterval, Date, console };
  vm.createContext(среда);
  vm.runInContext(fs.readFileSync(файл, 'utf8'), среда, { filename: файл });
  return { Лист: среда.module.exports, счёт };
}

// ---------------------------------------------------------------- проверки (каждая бросает при провале)
function ждать(условие, слова) { if (!условие) throw new Error(слова); }

function п1(файлы) {
  const тексты = { строка: { видна: true, текст: 'Предложить закончить' } };
  const а = загрузитьЛист(файлы.лист);
  ждать(typeof а.Лист.подключить === 'function', 'п1: у листа нет «подключить»');
  ждать(а.Лист.подключить({ идЛиста: 'лист-а' }), 'п1: лист не подключился (ноль найденного)');
  ждать(а.Лист.подключить({ идЛиста: 'лист-а' }), 'п1: второй раз лист не подключился');
  а.Лист.досрочно(тексты);
  ждать(а.счёт.кнопок === 1, 'п1: после двух «подключить» одного листа строк «Предложить закончить» ' + а.счёт.кнопок + ', а нужна 1');
  const б = загрузитьЛист(файлы.лист);
  б.Лист.подключить({ идЛиста: 'лист-а' });
  б.Лист.подключить({ идЛиста: 'лист-б' });
  б.Лист.досрочно(тексты);
  ждать(б.счёт.кнопок === 2, 'п1: два разных листа должны дать две строки, а дали ' + б.счёт.кнопок);
}

