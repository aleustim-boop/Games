const ПРОВЕРКИ = [['п1', п1], ['п2', п2], ['п3', п3], ['п4', п4], ['п5', п5]];

function прогнать(файлы) {
  const краснота = [];
  for (const [имя, проверка] of ПРОВЕРКИ) {
    try { проверка(файлы); } catch (е) { краснота.push(/^п[0-9]:/.test(е.message) ? е.message : имя + ': сбой проверки — ' + е.message); }
  }
  return краснота;
}

// ---------------------------------------------------------------- порча на копии
function копияСПорчей(порча) {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'ночь-п5-'));
  // Структура как в проекте: require домино-экрана ищет соседей по js/
  require('./пути-проекта.js').создатьПапкиКода(папка);
  fs.mkdirSync(path.join(папка, 'server', 'игры'), { recursive: true });
  const файлы = {};
  for (const [ключ, откуда] of Object.entries(НАСТОЯЩИЕ)) {
    const куда = ключ === 'сервер' ? path.join(папка, 'server', 'игры', 'домино.js') : require('./пути-проекта.js').путь(path.basename(откуда), папка);
    fs.copyFileSync(откуда, куда);
    файлы[ключ] = куда;
  }
  const текст = fs.readFileSync(файлы[порча.файл], 'utf8');
  if (!текст.includes(порча.было)) return null;
  fs.writeFileSync(файлы[порча.файл], текст.replace(порча.было, порча.стало));
  return файлы;
}

function порчаКраснеет(порча) {
  const файлы = копияСПорчей(порча);
  if (!файлы) { console.log('  порча ' + порча.номер + ': строка для порчи не найдена — ' + порча.зачем); process.exitCode = 2; return false; }
  const красное = прогнать(файлы);
  console.log('  порча ' + порча.номер + ' (' + порча.зачем + '): ' + (красное.length ? 'красная, как и нужно — ' + красное[0] : 'ЗЕЛЁНАЯ — проверка не поймала порчу'));
  // Красной считаем только порчу, пойманную своим пунктом: чужой сбой не в счёт.
  return красное.some(с => с.startsWith(порча.пункт + ':') && !/сбой проверки/.test(с));
}

