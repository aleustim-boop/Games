/** Русский адрес из браузера приходит закодированным — читаем его по-человечески. */
function декодировать(адрес) {
  try { return decodeURIComponent(адрес); } catch (о) { return адрес; }
}

let провалов = 0;
function проверить(условие, слова) {
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}

function ловецОшибок(страница, нашиЖеПомехи) {
  const красные = [];
  const наши = нашиЖеПомехи || /telegram-web-app\.js/;
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const откуда = (м.location && м.location() && м.location().url) || '';
    // Не считаем красным то, что не пустили мы сами: настоящий скрипт Telegram,
    // а во втором разделе — ещё и файл рисовальщика, который мы блокируем нарочно.
    if (наши.test(м.text() + ' ' + декодировать(откуда))) return;
    красные.push('консоль: ' + м.text() + (откуда ? ' [' + декодировать(откуда) + ']' : ''));
  });
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  return красные;
}

