/* Общие приёмы отсева: строки, которые заведомо не показываются игроку. */
function этоСлужебнаяСтрока(с) {
  const т = с.trim();
  if (/^[.#]/.test(т)) return true;                                  // селектор css
  if (/\.js\b|\.js$/.test(т)) return true;                           // путь к файлу
  if (!/\s/.test(т) && /^[a-zа-яё0-9_\-:.]+$/.test(т) && /[а-яё]/.test(т)) return true; // одно слово строчными: ключ, класс, id
  const слова = т.split(/\s+/);
  if (/[-_]/.test(т) && слова.every(с2 => /^[a-zа-яё0-9_\-:.]+$/.test(с2))) return true; // набор классов
  return false;
}

/* Строки js, которые пишутся в консоль или в исключения — игрок их не видит. */
function убратьОтладочныеСтроки(код) {
  return код.split('\n').filter(л => !/console\.(log|warn|error|info)|new Error\(/.test(л)).join('\n');
}

const естьКириллица = с => /[А-Яа-яЁёІіЇїЄє]/.test(с);

function убратьКомментарииJs(код) {
  return код
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/(^|[^:\\'"`])\/\/.*$/gm, '$1');
}

/* Строки-литералы js, содержащие кириллицу. ${…} заменяем на условное имя. */
function строкиИзJs(код) {
  const чистый = убратьКомментарииJs(код);
  const найдено = [];
  const образец = /'((?:[^'\\\n]|\\.)*)'|"((?:[^"\\\n]|\\.)*)"|`((?:[^`\\]|\\[\s\S])*)`/g;
  let м;
  while ((м = образец.exec(чистый))) {
    let с = м[1] !== undefined ? м[1] : м[2] !== undefined ? м[2] : м[3];
    с = с.replace(/\$\{[^}]*\}/g, 'Alex').replace(/\\n/g, ' ').replace(/\\(.)/g, '$1');
    if (естьКириллица(с)) найдено.push(с);
  }
  return найдено;
}

function раскодироватьСущности(с) {
  return с
    .replace(/&nbsp;/g, ' ').replace(/&mdash;/g, '—').replace(/&ndash;/g, '–')
    .replace(/&laquo;/g, '«').replace(/&raquo;/g, '»').replace(/&hellip;/g, '…')
    .replace(/&times;/g, '×').replace(/&amp;/g, '&').replace(/&quot;/g, '"')
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>');
}

/* Из html: текст между тегами, атрибуты-подписи и строки встроенных скриптов. */
function строкиИзHtml(html) {
  const найдено = [];
  const скрипты = [];
  let без = html.replace(/<!--[\s\S]*?-->/g, ' ');
  без = без.replace(/<script\b[^>]*>([\s\S]*?)<\/script>/gi, (_, тело) => { скрипты.push(тело); return ' '; });
  без = без.replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, ' ');
  for (const м of без.matchAll(/\b(aria-label|title|placeholder|alt)="([^"]*)"/g)) {
    const с = раскодироватьСущности(м[2]);
    if (естьКириллица(с)) найдено.push(с);
  }
  for (const [, текст] of без.matchAll(/>([^<]+)</g)) {
    const с = раскодироватьСущности(текст);
    if (естьКириллица(с)) найдено.push(с);
  }
  for (const тело of скрипты) найдено.push(...строкиИзJs(тело));
  return найдено;
}

function собратьСтроки() {
  const все = [];
  for (const ф of источники.html) {
    for (const с of строкиИзHtml(fs.readFileSync(path.join(корень, ф), 'utf8'))) все.push([с, ф]);
  }
  for (const { файл: ф, только } of источники.js) {
    let код = убратьОтладочныеСтроки(fs.readFileSync(path.join(корень, ф), 'utf8'));
    if (только) код = код.split('\n').filter(л => только.test(л)).join('\n');
    for (const с of строкиИзJs(код)) все.push([с, ф]);
  }
  return все;
}

/* Читает «ru|uk|en» из текста файла словаря (между первой парой обратных кавычек). */
function строкиСловаряИзТекста(текстФайла) {
  const м = /const строки = `([\s\S]*?)`;/.exec(текстФайла);
  return м ? м[1].split('\n').filter(с => с.trim()) : null;
}

function проверить(путьСловаря) {
  const ошибки = [];
  const Языки = require(require('./пути-проекта.js').рядомИлиВПроекте(путьСловаря, 'языки.js'));
  const содержимое = require(путьСловаря);
  const текстФайла = fs.readFileSync(путьСловаря, 'utf8');

  // 1. Устройство словаря.
  const строки = строкиСловаряИзТекста(текстФайла);
  if (!строки || !строки.length) ошибки.push('в словаре игры не найдено ни одной строки');
  const виденные = new Set();
  for (const с of строки || []) {
    const части = с.split('|');
    if (части.length !== 3 || части.some(ч => !ч.trim())) { ошибки.push('строка не из трёх частей: ' + с); continue; }
    const ключ = Языки.норм(части[0]);
    if (виденные.has(ключ)) ошибки.push('повтор ключа: ' + ключ);
    виденные.add(ключ);
  }
  const шаблоны = содержимое && содержимое.шаблоны;
  if (!Array.isArray(шаблоны)) ошибки.push('словарь не отдаёт список шаблонов');
  for (const запись of шаблоны || []) {
    if (!Array.isArray(запись) || запись.length !== 3 || !(запись[0] instanceof RegExp) || typeof запись[1] !== 'string' || typeof запись[2] !== 'string') {
      ошибки.push('шаблон не вида [RegExp, uk, en]: ' + String(запись && запись[0])); continue;
    }
    const скобок = new RegExp(запись[0].source + '|').exec('').length - 1;
    for (const п of [запись[1], запись[2]]) {
      for (const [, n] of п.matchAll(/\$(\d+)/g)) {
        if (Number(n) > скобок) ошибки.push('в шаблоне ' + запись[0] + ' $' + n + ' больше числа скобок (' + скобок + ')');
      }
    }
  }

  // 2. Покрытие.
  const все = собратьСтроки();
  if (!все.length) ошибки.push('не найдено ни одной русской строки в html и js — проверка слепая');
  const исключения = new Map(неПереводим.map(([с, причина]) => [Языки.норм(с), причина]));
  const уже = new Set();
  for (const [с, откуда] of все) {
    const ключ = Языки.норм(с);
    if (!ключ || уже.has(ключ) || этоСлужебнаяСтрока(ключ) || СЛУЖЕБНЫЕ_КАТАНА.test(ключ)) continue;
    уже.add(ключ);
    if (исключения.has(ключ)) continue;
    // След ${…} (слово Alex) подменяем то именем, то числом: фраза обязана переводиться хотя бы так.
    const варианты = [ключ, ключ + ' Alex', 'Alex ' + ключ, ключ + ' 5', '5 ' + ключ, ключ + 'Alex', 'Alex' + ключ,
      ключ.replace(/Alex/g, 'Оля'), ключ.replace(/Alex/g, '5')];
    // Слово может одинаково писаться по-русски и по-украински («Звук», «Слон») — тогда оно есть в словаре, а текст не меняется.
    // По-украински слово может совпасть с русским («Бот», «Кубик»), поэтому довольно того, что английский перевод есть.
    const переведено = Boolean(Языки.словарь[ключ]) || варианты.some(в => Языки.текст(в, 'en') !== в);
    if (!переведено) ошибки.push('нет перевода: «' + ключ + '» (' + откуда + ')');
  }
  // Образцы собранных фраз: имя «Оля» остаётся как есть, остальное переведено.
  for (const о of образцы) {
    for (const код of ['uk', 'en']) {
      const результат = Языки.текст(о, код);
      const остаток = результат.replace(/Оля|Оли/g, '');
      // В украинском кириллица законна, но русских букв ы, э, ъ, ё в нём нет.
      const русскоеОстаётся = код === 'uk' ? /[ыэъёЫЭЪЁ]/.test(остаток) : /[А-Яа-яЁё]/.test(остаток);
      if ((код === 'en' && результат === о) || русскоеОстаётся) {
        ошибки.push('образец не переведён на ' + код + ': «' + о + '» → «' + результат + '»');
      }
    }
  }
  return ошибки;
}

function ломающийЗапуск(папка) {
  let сработало = 0;
  const текстФайла = fs.readFileSync(словарьИгры, 'utf8');
  const строки = строкиСловаряИзТекста(текстФайла) || [];
  // Подготовка копии: словарь + общий словарь рядом, у каждой попытки своя подпапка.
  function копия(номер, исправитьТекст) {
    const подпапка = path.join(папка, 'п' + номер);
    fs.mkdirSync(подпапка, { recursive: true });
    fs.copyFileSync(общийСловарь, path.join(подпапка, 'языки.js'));
    const цель = path.join(подпапка, 'языки-катан.js');
    fs.writeFileSync(цель, исправитьТекст(текстФайла));
    return цель;
  }
  // Попытка А: вычёркиваем по одной строке, пока проверка не покраснеет «нет перевода» (хоть на одной — ок).
  let краснота = false;
  for (let i = 0; i < строки.length && !краснота; i++) {
    const цель = копия('А' + i, т => т.replace(строки[i] + '\n', ''));
    краснота = проверить(цель).some(о => о.startsWith('нет перевода'));
  }
  if (краснота) сработало++; else console.log('ЛОМАЮЩИЙ: вычёркивание строки не покраснело ни разу');
  // Попытка Б: пустая часть в строке.
  const цельБ = копия('Б', т => т.replace(строки[0], строки[0].split('|')[0] + '||' + строки[0].split('|')[2]));
  if (проверить(цельБ).some(о => о.startsWith('строка не из трёх частей'))) сработало++;
  else console.log('ЛОМАЮЩИЙ: пустой перевод не покраснел');
  // Попытка В: повтор ключа.
  const цельВ = копия('В', т => т.replace(строки[0], строки[0] + '\n' + строки[0]));
  if (проверить(цельВ).some(о => о.startsWith('повтор ключа'))) сработало++;
  else console.log('ЛОМАЮЩИЙ: повтор ключа не покраснел');
  // Попытка Г: вычёркиваем один ШАБЛОН — образец собранной фразы обязан остаться без перевода.
  const цельГ = копия('Г', т => т.split('\n').filter(л => !л.startsWith('    [/^Расстановка')).join('\n'));
  if (проверить(цельГ).some(о => о.startsWith('образец не переведён') && о.includes('Расстановка'))) сработало++;
  else console.log('ЛОМАЮЩИЙ: вычёркивание шаблона не покраснело');
  return сработало === 4;
}

