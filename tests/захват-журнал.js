/** Сыграть раунд до конца раскрытия. Ответ — разыгрался ли он (номер раунда вырос или партия кончилась). */
function сыгратьРаунд(м) {
  const до = м.сохранение();
  м.готово();
  м.часы.прошло(РАСКРЫТИЕ_МС);
  const после = м.сохранение();
  return !!до && !!после && (после.партия.раунд === до.партия.раунд + 1 || после.партия.завершена === true);
}

