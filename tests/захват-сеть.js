  const воЧто = словарьИзИсходника(исходник, 'ВО_ЧТО_ИГРАЕМ');
  проверить(!!воЧто, 'в общее/js/сеть.js нашёлся словарь ВО_ЧТО_ИГРАЕМ');
  проверить(!!воЧто && воЧто['захват'] === 'в захват', 'ВО_ЧТО_ИГРАЕМ: «захват» → «в захват»');
  const названия = словарьИзИсходника(исходник, 'НАЗВАНИЯ_ИГР');
  проверить(!!названия, 'в общее/js/сеть.js нашёлся словарь НАЗВАНИЯ_ИГР');
  проверить(!!названия && названия['захват'] === 'захват', 'НАЗВАНИЯ_ИГР: «захват» → «захват»');

  const с = поднятьСеть(исходник);
  проверить(!!с.Сеть && typeof с.Сеть.отправитьЧерновик === 'function', 'у Сети есть дверь отправитьЧерновик');
  if (!с.Сеть || typeof с.Сеть.отправитьЧерновик !== 'function') return;

