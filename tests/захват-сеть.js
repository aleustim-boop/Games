  const ключи = с.окно.localStorage.ключи().concat(с.окно.sessionStorage.ключи());
  проверить(ключи.indexOf('room_zahvat') !== -1, 'комната хранится под ключом room_zahvat (ключи: ' + ключи.join(', ') + ')');
