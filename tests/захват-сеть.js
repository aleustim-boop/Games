/* Вынуть объект-словарь из исходника по имени константы. Не нашёлся —
   null, и проверка краснеет: ноль найденного — провал, а не пропуск. */
function словарьИзИсходника(исходник, имя) {
  const найдено = исходник.match(new RegExp('const ' + имя + ' = (\\{[^}]*\\});'));
  if (!найдено) return null;
  try {
    return vm.runInNewContext('(' + найдено[1] + ')', {});
  } catch (сбой) {
    return null;
  }
}

