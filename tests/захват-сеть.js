async function дождаться() {
  for (let раз = 0; раз < 40; раз++) await new Promise(function (г) { setImmediate(г); });
}

/** Чем кончилось обещание двери: ответом или срывом. */
async function исход(обещание) {
  try {
    return { сорвалось: false, ответ: await обещание };
  } catch (ошибка) {
    return { сорвалось: true, ответ: null };
  }
}

