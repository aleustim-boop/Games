async function один(путьСети) {
  проверок = 0;
  провалов = 0;
  непойманныеОтказы.length = 0;
  let исходник;
  try {
    исходник = fs.readFileSync(путьСети, 'utf8');
  } catch (сбой) {
    проверить(false, 'файл сети не прочитан: ' + путьСети);
    return;
  }
  try {
    await прогнать(исходник);
  } catch (сбой) {
    проверить(false, 'прогон упал: ' + (сбой && сбой.message));
  }
  проверить(проверок >= ПОРОГ_ПРОВЕРОК, 'проверок не меньше порога ' + ПОРОГ_ПРОВЕРОК + ' (' + проверок + ')');
}

function сколькоНайдено(текст, найти) {
  return текст.split(найти).length - 1;
}

(async function () {
  if (!ЛОМАЕМ) {
    const файл = довод('сеть') || НАСТОЯЩИЙ_ФАЙЛ_СЕТИ;
    console.log('Файл сети: ' + файл);
    await один(файл);
    console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
    process.exit(провалов ? 1 : 0);
  }

  console.log('ЛОМАЮЩИЙ ЗАПУСК — каждая поломка обязана покраснеть');
  const исходник = fs.readFileSync(НАСТОЯЩИЙ_ФАЙЛ_СЕТИ, 'utf8');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-сеть-'));
  let покраснело = 0;
  let негодных = 0;
  /* Файл сети хранится с переводами строк CRLF (Windows); порчи записаны
     с «\n» — приводим их к тому переводу, что в файле. */
  const перевод = исходник.indexOf('\r\n') !== -1 ? '\r\n' : '\n';
  молча = true;
  for (let i = 0; i < ПОЛОМКИ.length; i++) {
    const поломка = {
      имя: ПОЛОМКИ[i].имя,
      найти: ПОЛОМКИ[i].найти.split('\n').join(перевод),
      заменить: ПОЛОМКИ[i].заменить.split('\n').join(перевод)
    };
    const раз = сколькоНайдено(исходник, поломка.найти);
    if (раз !== 1) {
      негодных++;
      console.log('ПРОВАЛ  «' + поломка.имя + '»: место порчи найдено ' + раз + ' раз, нужно ровно 1');
      continue;
    }
    const копия = path.join(папка, 'сеть-' + i + '.js');
    fs.writeFileSync(копия, исходник.replace(поломка.найти, function () { return поломка.заменить; }));
    await один(копия);
    if (провалов > 0) {
      покраснело++;
      console.log('покраснела      «' + поломка.имя + '» (провалов: ' + провалов + ')');
    } else {
      негодных++;
      console.log('НЕ ПОКРАСНЕЛА   «' + поломка.имя + '»');
    }
  }
  console.log('Поломок: ' + ПОЛОМКИ.length + ', покраснело: ' + покраснело + ', негодных: ' + негодных);
  console.log('Копии лежат в ' + папка);
  process.exit(покраснело === ПОЛОМКИ.length && !негодных ? 0 : 1);
})().catch(function (сбой) { console.error(сбой); process.exit(1); });
