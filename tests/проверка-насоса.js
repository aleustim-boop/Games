/* Проверка: насос ботов не умирает.

   Главное, что здесь проверяется, — три дороги, на которых комната могла
   бы встать навсегда:
     1. ход человека отклонён — насос обязан быть перезаведён;
     2. ход бота «не вышел» — ходит тот, чья очередь, в том же такте;
     3. насос всё-таки умер — сторож в уборщике поднимает его.

   Запуск: node проверка-насоса.js
*/

'use strict';

const ИГРА = require('path').resolve(__dirname, '..');   // корень проекта — от этого файла, а не зашитый
const комнаты = require(ИГРА + '/server/комнаты.js');
const партии = require(ИГРА + '/server/партия-по-сети.js');

let всёХорошо = true;
function проверить(что, правда, подробности) {
  console.log((правда ? '  ОК   ' : '  БЕДА ') + что + (подробности ? ' → ' + подробности : ''));
  if (!правда) всёХорошо = false;
}
function заголовок(строка) { console.log(''); console.log(строка); }

/** Стол: человек-хозяин и сколько-то ботов. Карты розданы. */
function столСБотами(сколькоБотов) {
  const создано = комнаты.создатьКомнату('1.1.1.1',
    { имя: 'Пётр', мест: сколькоБотов + 1 });
  const я = комнаты.найтиИгрока(создано.код, создано.пропуск);
  for (let счёт = 0; счёт < сколькоБотов; счёт++) {
    комнаты.сделатьХод(я.комната, я.ктоЯ, { действие: 'бот' });
  }
  комнаты.сделатьХод(я.комната, я.ктоЯ, { действие: 'начать' });
  return { комната: я.комната, ктоЯ: я.ктоЯ, код: создано.код, пропуск: создано.пропуск };
}

/** Ход за ботом и таймера нет — вот это и есть мёртвый насос. */
function насосМёртв(комната) {
  if (комната.этап !== 'игра') return false;
  const место = партии.чейХод(комната.партия);
  const игрок = место ? комната.игроки[место] : null;
  return Boolean(игрок && игрок.этоБот && !комната.таймерБота);
}

/* ---------- 1. Отклонённый ход перезаводит насос ---------- */
заголовок('1. Ход человека отклонён — насос жив');
const стол1 = столСБотами(1);
проверить('партия идёт', стол1.комната.этап === 'игра');
// Убиваем насос руками — так он выглядит после любой забытой дороги.
clearTimeout(стол1.комната.таймерБота);
стол1.комната.таймерБота = null;
проверить('насос погашен нарочно', стол1.комната.таймерБота === null);

const отказ = комнаты.сделатьХод(стол1.комната, стол1.ктоЯ,
  { действие: 'ходить', карта: { масть: '♠', достоинство: 'нет такой' } });
проверить('сервер отклонил негодный ход', отказ.принято === false, отказ.причина);
const ходЗаБотом1 = (function () {
  const место = партии.чейХод(стол1.комната.партия);
  const игрок = место ? стол1.комната.игроки[место] : null;
  return Boolean(игрок && игрок.этоБот);
})();
проверить('после отказа комната не мертва', !насосМёртв(стол1.комната),
          ходЗаБотом1 ? 'ход за ботом, таймер: ' + Boolean(стол1.комната.таймерБота)
                      : 'ход за человеком');

/* ---------- 2. «Не вышло» — ходит тот, чья очередь, в том же такте ---------- */
заголовок('2. Ход бота не вышел — партия всё равно движется');
const стол2 = столСБотами(3);
// Дожидаться очереди бота не будем: спросим прямо, кто ходит.
const ктоХодит2 = партии.чейХод(стол2.комната.партия);
const этоБот2 = стол2.комната.игроки[ктоХодит2].этоБот;

const настоящийХод = партии.ходЗаБота;
let первыйРаз = true;
партии.ходЗаБота = function (партия, место, уровень) {
  /* Первый вызов притворяется, что очередь ушла: ровно так выглядит
     «не вышло» из плана. Дальше ходим по-настоящему. */
  if (первыйРаз) { первыйРаз = false; return null; }
  return настоящийХод(партия, место, уровень);
};

const событиеДо = стол2.комната.номерСобытия;
if (этоБот2) {
  // Дёргаем насос так же, как это делает сработавший таймер.
  clearTimeout(стол2.комната.таймерБота);
  стол2.комната.таймерБота = null;
  комнаты.сделатьХод(стол2.комната, стол2.ктоЯ, { действие: 'бито' });   // отказ: не его ход
}
setTimeout(function () {
  партии.ходЗаБота = настоящийХод;
  проверить('комната не встала', !насосМёртв(стол2.комната));
  проверить('партия за это время двигалась',
            стол2.комната.номерСобытия >= событиеДо,
            'событий было ' + событиeДоБезопасно() + ', стало ' + стол2.комната.номерСобытия);
  шаг3();
}, 1500);

function событиeДоБезопасно() { return событиеДо; }

/* Законный ход человека по виду стола — те же вопросы правилам, что задаёт
   страница. Нужен части 3: пока очередь у человека, бот её не получит,
   а человек за этим столом сам не ходит. */
const правила = require(ИГРА + '/js/game.js');
function законныйХод(вид) {
  const рука = вид.мояРука || [];
  const стол = вид.стол || [];
  if (вид.фаза === 'защита') {
    for (let пара = 0; пара < стол.length; пара++) {
      if (стол[пара].защита) continue;
      for (let к = 0; к < рука.length; к++) {
        if (правила.бьёт(рука[к], стол[пара].атака, вид.козырь)) return { действие: 'отбить', карта: к, пара: пара };
      }
    }
    return { действие: 'беру' };
  }
  if (вид.фаза === 'атака') return { действие: 'ходить', карта: 0 };
  if (вид.могуПодкинуть) {
    const достоинства = правила.достоинстваНаСтоле({ стол: стол });
    for (let к = 0; к < рука.length; к++) if (достоинства.indexOf(рука[к].имя) !== -1) return { действие: 'ходить', карта: к };
  }
  return { действие: 'бито' };
}

/** Доиграть за человека до того мига, когда очередь у бота (или партия кончилась). */
function довестиДоХодаБота(стол) {
  for (let шаг = 0; шаг < 200; шаг++) {
    if (стол.комната.этап !== 'игра') return false;
    const место = партии.чейХод(стол.комната.партия);
    const игрок = место ? стол.комната.игроки[место] : null;
    if (игрок && игрок.этоБот) return true;
    const вид = комнаты.показатьИгроку(стол.комната, стол.ктоЯ);
    const ответ = комнаты.сделатьХод(стол.комната, стол.ктоЯ, законныйХод(вид));
    if (!ответ.принято) { console.log('  (законный ход человека отклонён: ' + ответ.причина + ')'); return false; }
  }
  return false;
}

/* ---------- 3. Сторож поднимает мёртвый насос ---------- */
function шаг3() {
  заголовок('3. Сторож в уборщике поднимает уснувший насос');
  const стол3 = столСБотами(2);
  /* Раньше здесь просто ждали очереди бота, а человек не ходил — и если
     первый ход выпадал человеку, бот очереди не получал никогда: проверка
     краснела через раз, как монетка. Теперь за человека ходим законно. */
  довестиДоХодаБота(стол3);
  // Ждём, пока очередь дойдёт до бота, и убиваем насос.
  ждатьХодаБота(стол3.комната, function (получилось) {
    if (!получилось) {
      проверить('дождались хода бота', false, 'за 5 секунд ход к боту не перешёл');
      конец();
      return;
    }
    clearTimeout(стол3.комната.таймерБота);
    стол3.комната.таймерБота = null;
    проверить('насос убит, комната мертва', насосМёртв(стол3.комната));

    комнаты.прибратьсяСейчас();   // ровно то, что уборщик делает каждые 3 секунды
    проверить('сторож поднял насос', !насосМёртв(стол3.комната),
              'таймер: ' + Boolean(стол3.комната.таймерБота));
    шаг4();
  });
}

/** Дождаться, когда ходить будет бот (боты ходят с паузой). */
function ждатьХодаБота(комната, дальше, попытка) {
  const счёт = попытка || 0;
  if (комната.этап !== 'игра') return дальше(false);
  const место = партии.чейХод(комната.партия);
  const игрок = место ? комната.игроки[место] : null;
  if (игрок && игрок.этоБот && комната.таймерБота) return дальше(true);
  if (счёт > 50) return дальше(false);
  setTimeout(function () { ждатьХодаБота(комната, дальше, счёт + 1); }, 100);
}

/* ---------- 4. Много отказов подряд: инвариант держится ---------- */
function шаг4() {
  заголовок('4. Сотня отказов подряд — комната живёт');
  const стол4 = столСБотами(3);
  let нарушений = 0;
  let проверок = 0;

  for (let раз = 0; раз < 100; раз++) {
    комнаты.сделатьХод(стол4.комната, стол4.ктоЯ,
      { действие: раз % 2 ? 'бито' : 'ходить', карта: { масть: '♣', достоинство: 'нет' } });
    проверок++;
    /* Инвариант из плана: после каждого запроса верно одно из трёх —
       партия кончена, ход за живым игроком, или заведён таймер бота. */
    if (насосМёртв(стол4.комната)) нарушений++;
  }
  проверить('после каждого из ста отказов комната жива', нарушений === 0,
            'нарушений: ' + нарушений + ' из ' + проверок);

  // И напоследок: партия должна дойти до конца сама, без наших подсказок.
  ждатьКонца(стол4.комната, 0);
}

function ждатьКонца(комната, попытка) {
  if (комната.этап !== 'игра') {
    проверить('партия доиграна до конца сама', true, 'этап: ' + комната.этап);
    return конец();
  }
  const место = партии.чейХод(комната.партия);
  const игрок = место ? комната.игроки[место] : null;
  if (игрок && !игрок.этоБот) {
    проверить('партия дошла до хода человека и ждёт его', true, 'ход за человеком');
    return конец();
  }
  if (попытка > 100) {
    проверить('партия не встала', false, 'за 10 секунд ничего не изменилось');
    return конец();
  }
  setTimeout(function () { ждатьКонца(комната, попытка + 1); }, 100);
}

function конец() {
  console.log('');
  console.log(всёХорошо ? 'ВСЁ СОШЛОСЬ' : 'ЕСТЬ БЕДЫ');
  process.exit(всёХорошо ? 0 : 1);
}
