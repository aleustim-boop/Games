/* =====================================================================
   Проверка: бот встречает гостя, который пришёл по ссылке-приглашению
   в конкретную игру («t.me/<бот>?start=invite_<метка>» — метку кладёт
   карточка js/похвастаться.js, ссылку собирает server/сервер.js).

   Настоящий bot/.env не читаем и не запускаем: копируем файлы bot/*.js
   и server/названия.js на отдельный стенд во временной папке (как это
   делает tests/проверка-бота-лаунчера.js), подкладываем ПОДДЕЛЬНЫЙ .env
   с выдуманным токеном. Разговор с Telegram тоже поддельный: подменяем
   https.request прямо в этом процессе (тот же приём, что «поддельный
   Telegram» в bot/проверка-стола.js, только там подменяют не https,
   а саму функцию вызовAPI, потому что стол-из-чата.js принимает её
   снаружи; бот.js так не умеет, поэтому подменяется сеть пониже).

   Бот требуется прямо в этом процессе (require), а не отдельным
   запуском: так проще поймать все его сетевые вызовы без обмена
   файлами между процессами. Бесконечный цикл ожидания новостей
   (getUpdates) не мешает — после всех сценариев процесс завершается
   принудительно, process.exit(), вместе с этим циклом.

   Запуск:            node tests/бот-приглашение-в-игру.js
   Только поломка:     node tests/бот-приглашение-в-игру.js --сломать
   ===================================================================== */

'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const https = require('https');
const { EventEmitter } = require('events');

const КОРЕНЬ = path.join(__dirname, '..');
const ИСХОДНЫЕ_НАЗВАНИЯ = path.join(КОРЕНЬ, 'server', 'названия.js');

let проверок = 0;
let провалов = 0;
const временныеПапки = [];

function проверить(описание, условие, подробности) {
  проверок++;
  if (условие) { console.log('  ок   — ' + описание); return; }
  провалов++;
  console.log('  СБОЙ — ' + описание + (подробности ? '\n         ' + подробности : ''));
}

function пауза(мс) { return new Promise(function (готово) { setTimeout(готово, мс); }); }

/* Выдуманный токен собран из кусочков — GitHub узнаёт токены Telegram
   по виду строки и присылает ложную тревогу об утечке, если написать
   его одной строкой (см. объяснение в tests/проверка-бота-лаунчера.js). */
function выдуманныйТокен() {
  const номерБота = [1, 2, 3, 4, 5, 6, 7, 8, 9, 0].join('');
  return номерБота + ':' + 'тест'.repeat(9);
}
const ТОКЕН = выдуманныйТокен();

// Адрес сервера комнат зашит в хвостик GAME_URL «?сервер=».
const АДРЕС_СЕРВЕРА_КОМНАТ = 'https://комнаты.пример:8790';
const GAME_URL = 'https://игра.пример/сборник?сервер=' + encodeURIComponent(АДРЕС_СЕРВЕРА_КОМНАТ);
// Тот же адрес игры, но без «?сервер=» — проектом такая настройка тоже
// поддерживается (см. рассказатьПроСерверКомнат в bot/бот.js): для неё
// хвостикСАдресом обязан всё равно отдать метку игры, просто без адреса.
const GAME_URL_БЕЗ_АДРЕСА = 'https://игра.пример/сборник';

// ---------------------------------------------------------------------------
// Поддельный Telegram: подменяем https.request на весь процесс
// ---------------------------------------------------------------------------

const ОТПРАВЛЕНО = [];       // {метод, тело} — все запросы вида sendMessage/sendPhoto
let очередьОбновлений = [];  // апдейты, которые отдаём на ближайший запрос getUpdates
let счётЗапросовGetUpdates = 0;  // сколько раз вообще спросили getUpdates — по нему видно,
                                  // что именно ТЕКУЩИЙ бот успел уйти в долгий сон (см. спросить())

https.request = function (опции, колбэк) {
  const запрос = new EventEmitter();
  запрос.end = function (телоBuf) {
    let тело = {};
    try { тело = телоBuf ? JSON.parse(телоBuf.toString('utf8')) : {}; } catch (ошибка) { /* не важно */ }
    const путь = String((опции && опции.path) || '');
    const метод = путь.slice(путь.lastIndexOf('/') + 1);

    function ответить(результат, задержкаМс) {
      setTimeout(function () {
        const ответ = new EventEmitter();
        ответ.setEncoding = function () {};
        ответ.statusCode = 200;
        колбэк(ответ);
        ответ.emit('data', JSON.stringify({ ok: true, result: результат }));
        ответ.emit('end');
      }, задержкаМс || 0);
    }

    if (метод === 'getUpdates') {
      счётЗапросовGetUpdates++;
      if (очередьОбновлений.length) {
        const пачка = очередьОбновлений;
        очередьОбновлений = [];
        ответить(пачка, 0);
      } else {
        /* Пусто отдавать не сразу, а с большой задержкой: у каждого сценария
           свой стенд и свой процесс require(), но https.request пропатчен
           один на весь тест, а старые «отработавшие» боты не умирают —
           их while(true) продолжает крутиться в фоне. Если отдать им пустой
           ответ быстро, они снова спросят getUpdates и могут перехватить
           очередь апдейтов, приготовленную уже для СЛЕДУЮЩЕГО сценария —
           гонка, из-за которой ломающий запуск однажды не покраснел (старый
           исправный бот увёл апдейт у сломанного). 10 минут — заведомо
           больше времени жизни всего прогона проверки. */
        ответить([], 10 * 60 * 1000);
      }
      return;
    }

    ОТПРАВЛЕНО.push({ метод: метод, тело: тело });
    if (метод === 'getMe') { ответить({ username: 'ТестБот' }); return; }
    if (метод === 'setChatMenuButton') { ответить(true); return; }
    ответить({ message_id: 1 });
  };
  запрос.on = EventEmitter.prototype.on.bind(запрос);
  запрос.destroy = function () {};
  return запрос;
};

