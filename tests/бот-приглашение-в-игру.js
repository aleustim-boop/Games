/** Собираем стенд. сломать=true — вырезаем из bot/бот.js ветку, которая
    отвечает на приглашение в конкретную игру (для ломающего запуска).
    Не нашли, что вырезать, — это сама по себе беда: значит проверка
    смотрит не туда, а не что всё исправно. */
function собратьСтенд(сломать, безАдресаСервера) {
  const рут = fs.mkdtempSync(path.join(os.tmpdir(), 'приглашение-в-игру-'));
  временныеПапки.push(рут);
  const папкаБота = path.join(рут, 'bot');
  const папкаСервера = path.join(рут, 'server');
  fs.mkdirSync(папкаБота);
  fs.mkdirSync(папкаСервера);

  const МАРКЕР_ВЕТКИ = 'if (await ответитьНаПриглашениеВИгру(сообщение, имяБота)) return;';
  let вырезали = false;

  for (const имя of fs.readdirSync(path.join(КОРЕНЬ, 'bot'))) {
    if (!имя.endsWith('.js') || имя.indexOf('проверка-') === 0) continue;
    let текст = fs.readFileSync(path.join(КОРЕНЬ, 'bot', имя), 'utf8');
    if (сломать && имя === 'бот.js') {
      if (текст.indexOf(МАРКЕР_ВЕТКИ) !== -1) {
        текст = текст.split(МАРКЕР_ВЕТКИ).join('');
        вырезали = true;
      }
    }
    fs.writeFileSync(path.join(папкаБота, имя), текст, 'utf8');
  }
  if (сломать && !вырезали) {
    throw new Error('ломающий запуск: в bot/бот.js не нашлась строка с вызовом ' +
      'ответитьНаПриглашениеВИгру — нечего вырезать, проверку чинить раньше, чем ' +
      'верить её зелёному цвету');
  }

  fs.copyFileSync(ИСХОДНЫЕ_НАЗВАНИЯ, path.join(папкаСервера, 'названия.js'));
  fs.copyFileSync(path.join(path.dirname(ИСХОДНЫЕ_НАЗВАНИЯ), 'inline-столы.js'), path.join(папкаСервера, 'inline-столы.js'));
  fs.mkdirSync(path.join(папкаСервера, '..', 'js'), { recursive: true });
  fs.copyFileSync(path.join(path.dirname(ИСХОДНЫЕ_НАЗВАНИЯ), '..', 'js', 'языки.js'), path.join(папкаСервера, '..', 'js', 'языки.js'));
  const адресИгрыДляСтенда = безАдресаСервера ? GAME_URL_БЕЗ_АДРЕСА : GAME_URL;
  fs.writeFileSync(path.join(папкаБота, '.env'),
    'BOT_TOKEN=' + ТОКЕН + '\nGAME_URL=' + адресИгрыДляСтенда + '\n', 'utf8');

  return path.join(папкаБота, 'бот.js');
}

/** Одно личное или групповое сообщение «от игрока» в формате апдейта Telegram. */
function сообщение(номер, имя, типЧата, текст) {
  return {
    update_id: Math.floor(Math.random() * 1e9),
    message: {
      message_id: 1,
      chat: { id: номер, type: типЧата },
      from: { id: номер, first_name: имя, is_bot: false },
      text: текст
    }
  };
}

/** Запускаем бота на стенде с одним апдейтом в очереди и ждём его ответ
    (sendMessage или sendPhoto). Каждый сценарий — свежий стенд (собратьСтенд
    возвращает уникальный путь), поэтому require() не путает сценарии между
    собой кешем модулей и не делит на всех один файл статистики. */
async function спросить(путьКБоту, апдейт) {
  очередьОбновлений = [апдейт];
  const началоОтправок = ОТПРАВЛЕНО.length;
  const счётДоЗапроса = счётЗапросовGetUpdates;

  require(путьКБоту);   // запускает работать() тут же, внутри процесса проверки

  for (let раз = 0; раз < 150; раз++) {
    const новые = ОТПРАВЛЕНО.slice(началоОтправок);
    if (новые.some(function (з) { return з.метод === 'sendMessage' || з.метод === 'sendPhoto'; })) break;
    await пауза(20);
  }

  /* Ждём ещё и ВТОРОЙ запрос getUpdates от этого же (только что созданного)
     бота — он придёт пустым и уложит бота в десятиминутный сон. Первый
     запрос забрал наш апдейт (+1 к счётчику), второй — уже пустой (+1 ещё).
     Не дождаться этого — значит перейти к следующему сценарию, пока бот ещё
     может проснуться и перехватить чужую очередь апдейтов (гонка, из-за
     которой ломающий запуск однажды не покраснел). */
  for (let раз = 0; раз < 150 && счётЗапросовGetUpdates < счётДоЗапроса + 2; раз++) {
    await пауза(10);
  }

  const новые = ОТПРАВЛЕНО.slice(началоОтправок)
    .filter(function (з) { return з.метод === 'sendMessage' || з.метод === 'sendPhoto'; });
  return новые[новые.length - 1] || null;
}

/** Первая кнопка первой строки клавиатуры ответа — там, где у наc «Играть». */
function перваяКнопка(ответ) {
  const клавиши = ответ && ответ.тело && ответ.тело.reply_markup && ответ.тело.reply_markup.inline_keyboard;
  return (клавиши && клавиши[0] && клавиши[0][0]) || null;
}

function текстОтвета(ответ) {
  return String((ответ && ответ.тело && (ответ.тело.text || ответ.тело.caption)) || '');
}

