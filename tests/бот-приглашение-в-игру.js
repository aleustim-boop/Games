async function основныеСценарии() {
  console.log('=== Проверка: бот на приглашение в конкретную игру ===\n');

  // 1) invite_shashki — метка известной игры
  const стенд1 = собратьСтенд(false);
  const ответ1 = await спросить(стенд1, сообщение(111, 'Игорь', 'private', '/start invite_shashki'));
  const текст1 = текстОтвета(ответ1);
  проверить('на invite_shashki в тексте есть «Вас зовут сыграть в шашки»',
    текст1.indexOf('Вас зовут сыграть в шашки') !== -1, 'текст был: ' + текст1);
  const кнопка1 = перваяКнопка(ответ1);
  проверить('кнопка называется «Играть»', !!кнопка1 && кнопка1.text === 'Играть',
    'кнопка была: ' + JSON.stringify(кнопка1));
  проверить('ссылка кнопки ведёт в мини-приложение с меткой shashki',
    !!кнопка1 && typeof кнопка1.url === 'string' &&
    кнопка1.url.indexOf('https://t.me/ТестБот/BoardGames?startapp=shashki') === 0,
    'url был: ' + (кнопка1 && кнопка1.url));

  // 2) invite без метки — прежний общий ответ
  const стенд2 = собратьСтенд(false);
  const текст2 = текстОтвета(await спросить(стенд2, сообщение(112, 'Оля', 'private', '/start invite')));
  проверить('на «/start invite» без метки — обычное приветствие, а не про игру',
    текст2.indexOf('Жмите «Играть» и выбирайте') !== -1 && текст2.indexOf('Вас зовут сыграть') === -1,
    'текст был: ' + текст2);

  // 3) invite_nope — метка не из таблицы игр
  const стенд3 = собратьСтенд(false);
  const текст3 = текстОтвета(await спросить(стенд3, сообщение(113, 'Петя', 'private', '/start invite_nope')));
  проверить('на незнакомую метку invite_nope — тоже обычное приветствие',
    текст3.indexOf('Жмите «Играть» и выбирайте') !== -1 && текст3.indexOf('Вас зовут сыграть') === -1,
    'текст был: ' + текст3);

  // 4) кириллица в хвосте — не проходит проверку допустимых знаков
  const стенд4 = собратьСтенд(false);
  const ответ4 = await спросить(стенд4, сообщение(114, 'Настя', 'private', '/start invite_шашкидурак'));
  const текст4 = текстОтвета(ответ4);
  проверить('кириллический мусор в метке — обычное приветствие, без мусора в ответе',
    текст4.indexOf('Вас зовут сыграть') === -1 && текст4.indexOf('шашкидурак') === -1,
    'текст был: ' + текст4);

  // 5) пробелы после метки — тоже не считается ссылкой-приглашением в игру
  const стенд5 = собратьСтенд(false);
  const ответ5 = await спросить(стенд5, сообщение(115, 'Дима', 'private', '/start invite_shashki лишнееслово'));
  const текст5 = текстОтвета(ответ5);
  проверить('хвост с пробелами после метки — обычное приветствие, без мусора в ответе',
    текст5.indexOf('Вас зовут сыграть') === -1 && текст5.indexOf('лишнееслово') === -1,
    'текст был: ' + текст5);

  // 6) группа: /start не должен вести себя как приглашение в игру
  const стенд6 = собратьСтенд(false);
  const ответ6 = await спросить(стенд6, сообщение(-600, 'Компания', 'group', '/start invite_shashki'));
  const текст6 = текстОтвета(ответ6);
  проверить('в группе «/start invite_shashki» не трогается — обычный групповой ответ',
    текст6.indexOf('Напишите /играть') !== -1 && текст6.indexOf('Вас зовут сыграть') === -1,
    'текст был: ' + текст6);

  // 7) статистика: заход по invite_shashki всё ещё считается «приглашением»
  const файлСтатистики = path.join(path.dirname(стенд1), 'данные', 'статистика.json');
  let данныеСтатистики = null;
  try { данныеСтатистики = JSON.parse(fs.readFileSync(файлСтатистики, 'utf8')); } catch (ошибка) { /* см. ниже */ }
  const записьЧеловека = данныеСтатистики && данныеСтатистики.люди && данныеСтатистики.люди['111'];
  проверить('заход по ссылке-приглашению в игру засчитан в статистике как «приглашение»',
    !!записьЧеловека && записьЧеловека.источник === 'приглашение',
    'файл: ' + файлСтатистики + ', запись: ' + JSON.stringify(записьЧеловека));

  // 8) GAME_URL без «?сервер=» — метка игры всё равно обязана попасть
  // в ссылку (замечание ревьюера: раньше хвостикСАдресом без адреса
  // отдавал пустую строку целиком, и кнопка «Играть» вела не в ту игру,
  // о которой говорит текст приглашения).
  const стенд8 = собратьСтенд(false, true);
  const ответ8 = await спросить(стенд8, сообщение(116, 'Гриша', 'private', '/start invite_shashki'));
  const текст8 = текстОтвета(ответ8);
  проверить('без адреса сервера в GAME_URL текст приглашения тот же — «Вас зовут сыграть в шашки»',
    текст8.indexOf('Вас зовут сыграть в шашки') !== -1, 'текст был: ' + текст8);
  const кнопка8 = перваяКнопка(ответ8);
  проверить('без адреса сервера ссылка кнопки «Играть» всё равно несёт метку игры (startapp=shashki)',
    !!кнопка8 && кнопка8.url === 'https://t.me/ТестБот/BoardGames?startapp=shashki',
    'url был: ' + (кнопка8 && кнопка8.url));
  проверить('без адреса сервера в ссылке нет лишнего хвостика «_-» (адреса там и не должно быть)',
    !!кнопка8 && кнопка8.url.indexOf('_-') === -1,
    'url был: ' + (кнопка8 && кнопка8.url));
}

async function ломающийЗапуск() {
  console.log('\n=== Ломающий запуск: ветка ответа на приглашение в игру вырезана ===');
  const стендСломанный = собратьСтенд(true);
  const ответ = await спросить(стендСломанный, сообщение(211, 'Игорь', 'private', '/start invite_shashki'));
  const текст = текстОтвета(ответ);
  const покраснело = текст.indexOf('Вас зовут сыграть в шашки') === -1;
  if (покраснело) {
    console.log('  ок   — без ветки ответа бот честно вернулся к общему приветствию ' +
      '(проверка умеет ловить эту поломку)');
  } else {
    провалов++;
    console.log('  СБОЙ — вырезали ветку ответа, а бот всё равно ответил как для приглашения в игру: ' +
      'проверка эту поломку не ловит. Текст был: ' + текст);
  }
  проверок++;
}

async function главная() {
  const толькоЛомающий = process.argv.indexOf('--сломать') !== -1;

  try {
    if (!толькоЛомающий) await основныеСценарии();
    await ломающийЗапуск();
  } finally {
    for (const папка of временныеПапки) {
      try { fs.rmSync(папка, { recursive: true, force: true }); } catch (ошибка) { /* временная папка не критична */ }
    }
  }

  console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);
  process.exit(провалов === 0 ? 0 : 1);
}

главная().catch(function (ошибка) {
  console.error('Проверка упала с технической ошибкой: ' + ошибка.stack);
  process.exit(1);
});
