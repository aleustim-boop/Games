/* Подменить модуль копией ДО того, как его подключат (тот же приём,
   что в подбор-за-открытый-стол-сервер.js). */
function подменитьКопией(имяФайла, путьКопии) {
  if (!путьКопии) return;
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: ' + имяФайла + ' взят из копии ' + путьКопии + ' ***');
  const настоящий = require.resolve(path.join(КОРЕНЬ, 'server', имяФайла));
  const копия = new Module(настоящий, module);
  копия.filename = настоящий;
  копия.paths = Module._nodeModulePaths(path.dirname(настоящий));
  require.cache[настоящий] = копия;
  копия._compile(fs.readFileSync(путьКопии, 'utf8'), настоящий);
  копия.loaded = true;
}
подменитьКопией('сервер.js', довод('--копия-сервера='));

