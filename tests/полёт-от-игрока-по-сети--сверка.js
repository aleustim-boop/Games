'use strict';

/* =====================================================================
   СВЕРКА: сопоставляет то, что засёк зонд в браузере (откуда прилетела
   карта), с тем, что независимо рассказал сервер (кто её положил на самом
   деле). Совпадений и расхождений здесь нет заранее — числа получаются
   только из двух настоящих источников:

     1) tests/зонд-полёта-карт.js — работает В БРАУЗЕРЕ, перехватывает
        window.ДвижениеКарт.узел и запоминает, какой узел был передан
        «родиной» для каждой НОВОЙ карты соперника. Дамп берётся так:
            JSON.stringify(window.ЗондПолёта.полёты())
        и сохраняется в файл (первый довод этого скрипта).

     2) tests/полёт-от-игрока-по-сети.js — работает В NODE, сидит за
        столом настоящим игроком и печатает КАЖДОЕ «СОБЫТИЕ_JSON …»
        из настоящего ответа сервера (поле «событие», server/партия-по-сети.js
        составляет его САМ, никак не заглядывая в браузерную угадку).
        Из вывода этого процесса нужно выбрать строки «СОБЫТИЕ_JSON »
        и положить их JSON-массивом в файл (второй довод) — например так:

            node -e "
              const fs=require('fs');
              const т=fs.readFileSync('журнал-напарника.txt','utf8');
              const с=т.split(/\r?\n/).filter(x=>x.startsWith('СОБЫТИЕ_JSON '));
              fs.writeFileSync('события.json', JSON.stringify(с.map(x=>JSON.parse(x.slice(13)))));
            "

   Запуск:
       node tests/полёт-от-игрока-по-сети--сверка.js полёты.json события.json

   КАК СОПОСТАВЛЯЮТСЯ ЗАПИСИ. Одна и та же карта (масть+имя) в течение
   одной раздачи может лечь на стол НЕСКОЛЬКО раз подряд — её могли забрать
   в руку («Беру») и разыграть заново. Поэтому записи с одинаковым ключом
   сопоставляются ПО ВРЕМЕНИ: каждому событию подбирается ближайший по времени
   полёт той же карты в окне ~3 сек. Так пропавший полёт (или событие) не
   сдвигает очередь и не вызывает ложных обвинений соседних событий.
   Свои события (кто-то — это же наш собственный игрок) пропускаются и в очереди
   зонда мест не занимают: зонд свои карты не перехватывает вовсе (см. «Игрок 1» —
   в этой проверке она соответствует человеку/автоигроку в браузере).
   ===================================================================== */

const fs = require('fs');

const ФАЙЛ_ПОЛЁТОВ = process.argv[2];
const ФАЙЛ_СОБЫТИЙ = process.argv[3];
/* Имя места браузера (того, за кем сидел тестировщик). Оно у Node-напарника,
   который писал файл событий, ВСЕГДА выглядит «чужим» («своё»=false) — поле
   «своё» верно только для собственного взгляда того напарника, который вёл
   журнал, а не для браузера. Поэтому браузерные ходы дополнительно исключаем
   по имени: иначе они попадали бы в очередь как «требуют полёта», хотя зонд
   их никогда не перехватывает (это же родной, не чужой, узел). */
const ИМЯ_БРАУЗЕРА = process.argv[4] || 'Игрок 1';

if (!ФАЙЛ_ПОЛЁТОВ || !ФАЙЛ_СОБЫТИЙ) {
  console.error('Скажите оба файла: node tests/полёт-от-игрока-по-сети--сверка.js полёты.json события.json [имя-браузера]');
  process.exit(1);
}

const полёты = JSON.parse(fs.readFileSync(ФАЙЛ_ПОЛЁТОВ, 'utf8'));
let события = JSON.parse(fs.readFileSync(ФАЙЛ_СОБЫТИЙ, 'utf8'))
  .slice()
  .sort((а, б) => а.времяМС - б.времяМС);

if (process.argv[5] === '--сломать') {
  const индекс = события.findIndex((соб, i) => i > события.length / 2 && соб.действие === 'ход');
  if (индекс >= 0) {
    события[индекс] = { ...события[индекс], номерМеста: (события[индекс].номерМеста % 4) + 1 };
  }
}

// Только события, у которых вообще есть карта и понятно, чьё место —
// «беру»/«бито» сюда не попадают: у них нет {карта}, разбирать нечего.
const ДЕЙСТВИЯ_С_КАРТОЙ = ['ход', 'подкинул', 'отбил', 'перевёл'];
const ОКНО_ПОИСКА_МС = 3000;

const очередьПолётовПоКлючу = new Map();
полёты.forEach((п) => {
  if (!очередьПолётовПоКлючу.has(п.ключ)) очередьПолётовПоКлючу.set(п.ключ, []);
  очередьПолётовПоКлючу.get(п.ключ).push(п);
});

const использованныеПолёты = new Set();

const строки = [];
for (const соб of события) {
  if (!ДЕЙСТВИЯ_С_КАРТОЙ.includes(соб.действие)) continue;
  if (соб.кто === ИМЯ_БРАУЗЕРА) continue;

  const очередь = очередьПолётовПоКлючу.get(соб.ключ) || [];

  let лучший = null;
  let лучшаяРазница = Infinity;

  for (let i = 0; i < очередь.length; i++) {
    const ID = соб.ключ + ':' + i;
    if (использованныеПолёты.has(ID)) continue;

    const полёт = очередь[i];
    if (typeof полёт.времяМС !== 'number') continue;

    const разница = Math.abs(полёт.времяМС - соб.времяМС);
    if (разница <= ОКНО_ПОИСКА_МС && разница < лучшаяРазница) {
      лучший = { полёт, ID, разница };
      лучшаяРазница = разница;
    }
  }

  if (!лучший) {
    строки.push({ событие: соб, полёт: null, класс: 'не_засечено' });
    continue;
  }

  использованныеПолёты.add(лучший.ID);
  const полёт = лучший.полёт;

  let класс;
  const номерРодины = полёт.родина && полёт.родина.номерМеста;
  if (!номерРодины) {
    класс = 'из_середины';
  } else if (String(номерРодины) === String(соб.номерМеста)) {
    класс = 'от_своей_плашки';
  } else {
    класс = 'ОТ_ЧУЖОЙ_ПЛАШКИ';
  }
  строки.push({ событие: соб, полёт, класс });
}

/* ---------------------------------------------------------------------
   Печать: сначала таблица по видам хода, потом каждая находка «чужая
   плашка» отдельной строкой — с неё и начинается разговор со штабом.
   --------------------------------------------------------------------- */

const поДействиям = new Map();
for (const запись of строки) {
  const действие = запись.событие.действие;
  if (!поДействиям.has(действие)) {
    поДействиям.set(действие, { от_своей_плашки: 0, из_середины: 0, ОТ_ЧУЖОЙ_ПЛАШКИ: 0, не_засечено: 0 });
  }
  поДействиям.get(действие)[запись.класс]++;
}

console.log('=== Сверка полёта карт: зонд браузера против события сервера ===');
console.log('Всего чужих карт с картой в событии: ' + строки.length);
console.log('');
console.log('По видам хода (своя плашка / середина / ЧУЖАЯ плашка / не засечено зондом):');
for (const [действие, счёт] of поДействиям) {
  console.log('  ' + действие.padEnd(10) + ' — ' +
    счёт.от_своей_плашки + ' / ' + счёт.из_середины + ' / ' +
    счёт.ОТ_ЧУЖОЙ_ПЛАШКИ + ' / ' + счёт.не_засечено);
}

const поломки = строки.filter((з) => з.класс === 'ОТ_ЧУЖОЙ_ПЛАШКИ');
console.log('');
if (поломки.length) {
  console.log('НАЙДЕНО: карта прилетела от ЧУЖОЙ плашки — ' + поломки.length + ' раз(а):');
  for (const з of поломки) {
    console.log('  ход «' + з.событие.сыройТекст + '» (должно быть место ' + з.событие.номерМеста +
      '), а зонд поймал родину: ' + JSON.stringify(з.полёт.родина));
  }
} else {
  console.log('Карт «от чужой плашки» не найдено.');
}

const незасеченные = строки.filter((з) => з.класс === 'не_засечено');
if (незасеченные.length) {
  console.log('');
  console.log('Не удалось сопоставить с зондом (в дампе не хватило записей на этот ключ) — ' +
    незасеченные.length + ':');
  for (const з of незасеченные) console.log('  ' + з.событие.сыройТекст);
}

process.exit(поломки.length ? 1 : 0);
