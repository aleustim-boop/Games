// Проверка окна карты «Захвата» (этап П6, ТЗ 8.4 «Окно карты»): ЗахватСтол.замеритьОкно и местоКарты с окном.
// Запуск: node tests/захват-окно-карты.js
// Довод --файл <путь> — взять копию игры/захват/захват-стол.js (рядом должны лежать захват-правила.js,
//                       захват-карта-вид.js, захват-карты.js); так делаются ломающие запуски.
// Без доводов проверка сама делает копии во временной папке, портит их и требует провала.
// Документ поддельный: экран 390×844, капсулы игроков кончаются на 120, наибольший пульт 200.
// «Фаза» здесь — нынешняя высота пульта: в итоге раунда он выше, чем в расстановке, под листом его нет.
'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const аргументы = process.argv.slice(2);
function довод(имя) {
  const и = аргументы.indexOf(имя);
  return и === -1 ? null : аргументы[и + 1];
}
const путьСтола = довод('--файл') || path.join(КОРЕНЬ, 'игры', 'захват', 'захват-стол.js');
const этоЛомающийЗапуск = !!довод('--файл');

const Правила = require(path.join(КОРЕНЬ, 'игры', 'захват', 'захват-правила.js'));
const КартаВид = require(path.join(КОРЕНЬ, 'игры', 'захват', 'захват-карта-вид.js'));
const ЗахватСтол = require(путьСтола);

// ---------- счёт проверок ----------

let пройдено = 0;
const провалы = [];
function проверка(название, условие, подробность) {
  if (условие) {
    пройдено++;
    return;
  }
  провалы.push(название);
  console.log('ПРОВАЛ: ' + название + (подробность ? ' — ' + подробность : ''));
}

const близко = function (а, б) { return Math.abs(а - б) <= 0.5; };

// ---------- поддельный экран ----------

// экран: { ширина, высота, низКапсул, наибольший, поле, отступСнизу, высотаПульта }.
// Узел карты — на весь экран (П2); пульт прижат к низу содержимого и растёт вверх.
function сделатьДокумент(экран) {
  const отступ = экран.поле + экран.отступСнизу;
  const рамки = {
    'захват-карта': { left: 0, top: 0, right: экран.ширина, bottom: экран.высота },
    'захват-игроки': { left: 0, top: экран.низКапсул - 36, right: экран.ширина, bottom: экран.низКапсул },
    'экран-игры': { left: 0, top: 0, right: экран.ширина, bottom: экран.высота },
    'захват-пульт': { left: 0, top: экран.высота - отступ - экран.высотаПульта, right: экран.ширина, bottom: экран.высота - отступ }
  };
  const узлы = {};
  Object.keys(рамки).forEach(function (id) {
    узлы[id] = { id: id, getBoundingClientRect: function () { return Object.assign({}, рамки[id]); } };
  });
  return {
    getElementById: function (id) { return узлы[id] || null; },
    defaultView: {
      getComputedStyle: function (у) {
        const экранИгры = у && у.id === 'экран-игры';
        return {
          paddingBottom: экранИгры ? отступ + 'px' : '0px',
          borderBottomWidth: '0px',
          getPropertyValue: function (имя) { return имя === '--захват-пульт-наибольший' ? экран.наибольший + 'px' : ''; }
        };
      }
    }
  };
}

const ТЕЛЕФОН = { ширина: 390, высота: 844, низКапсул: 120, наибольший: 200, поле: 12, отступСнизу: 20 };
const УЗКИЙ = { ширина: 320, высота: 640, низКапсул: 100, наибольший: 180, поле: 8, отступСнизу: 0 };
// Нынешняя высота пульта в разных фазах: расстановка с чипами, итог раунда, без чипов, под листом (скрыт).
const ФАЗЫ = { расстановка: 160, итог: 188, приказы: 120, подЛистом: 0 };

function сделатьПартию() {
  return Правила.новаяПартия({ игроки: ['a', 'бот-1', 'бот-2'], люди: ['a'], новичок: 'a' }, function () { return 0.5; });
}

// ---------- проверки ----------

function проверитьРазметку() {
  const html = fs.readFileSync(path.join(КОРЕНЬ, 'захват.html'), 'utf8');
  ['захват-карта', 'захват-игроки', 'экран-игры'].forEach(function (id) {
    проверка('в захват.html есть узел #' + id + ' (ноль найденного — провал)', html.indexOf('id="' + id + '"') !== -1);
  });
  const css = fs.readFileSync(path.join(КОРЕНЬ, 'игры/захват/style-захват.css'), 'utf8');
  проверка('в style-захват.css задан --захват-пульт-наибольший (ноль найденного — провал)',
    /--захват-пульт-наибольший:\s*\d+px/.test(css));
  проверка('стол отдаёт замеритьОкно', typeof ЗахватСтол.замеритьОкно === 'function');
}

function проверитьЗамер() {
  const окно = ЗахватСтол.замеритьОкно(сделатьДокумент(Object.assign({ высотаПульта: ФАЗЫ.расстановка }, ТЕЛЕФОН)));
  // верх = 120 + 8; низ = 844 − (12 + 20) − 200 − 8.
  проверка('окно 390×844: верх = низ капсул + 8 = 128, низ = 844 − 32 − 200 − 8 = 604',
    !!окно && близко(окно.верх, 128) && близко(окно.низ, 604), JSON.stringify(окно));
  проверка('замерить нечем (узлов нет) — null', ЗахватСтол.замеритьОкно({ getElementById: function () { return null; } }) === null);
  const безВида = сделатьДокумент(Object.assign({ высотаПульта: 100 }, ТЕЛЕФОН));
  delete безВида.defaultView;
  проверка('без defaultView — null, стол не падает', ЗахватСтол.замеритьОкно(безВида) === null);
}

function проверитьМестоВОкне() {
  const партия = сделатьПартию();
  const окно = ЗахватСтол.замеритьОкно(сделатьДокумент(Object.assign({ высотаПульта: ФАЗЫ.расстановка }, ТЕЛЕФОН)));
  проверка('окно замерено (ноль найденного — провал)', !!окно);
  if (!окно) return;
  const место = ЗахватСтол.местоКарты(партия, 390, 844, 0, окно);
  const полная = КартаВид.геометрия(Правила.картаПартии(партия), 390);
  проверка('карта целиком в окне: верх ≥ 128, низ ≤ 604, по ширине в экране',
    место.y >= окно.верх - 0.5 && место.y + место.высота <= окно.низ + 0.5 && место.x >= -0.5 && место.x + место.ширина <= 390.5,
    JSON.stringify(место));
  проверка('центр карты по x = 195', близко(место.x + место.ширина / 2, 195), JSON.stringify(место));
  проверка('Остров в окно влезает без уменьшения (×1)', близко(место.ширина, полная.ширина) && близко(место.высота, полная.высота),
    JSON.stringify([место, полная.высота]));
  проверка('карта по центру окна по высоте', близко(место.y + место.высота / 2, (окно.верх + окно.низ) / 2), JSON.stringify(место));

  // Узкий экран 320×640: окно ниже карты — карта уменьшается и всё равно целиком в окне.
  const узкоеОкно = ЗахватСтол.замеритьОкно(сделатьДокумент(Object.assign({ высотаПульта: ФАЗЫ.итог }, УЗКИЙ)));
  проверка('узкий экран: окно замерено', !!узкоеОкно, JSON.stringify(узкоеОкно));
  if (узкоеОкно) {
    const узко = ЗахватСтол.местоКарты(партия, 320, 640, 0, узкоеОкно);
    проверка('узкий экран: карта целиком в окне и по центру по x', узко.y >= узкоеОкно.верх - 0.5 &&
      узко.y + узко.высота <= узкоеОкно.низ + 0.5 && близко(узко.x + узко.ширина / 2, 160), JSON.stringify([узко, узкоеОкно]));
  }

  // Без окна — прежнее поведение (экран и онлайн до П7 зовут местоКарты без пятого довода).
  const безОкна = ЗахватСтол.местоКарты(партия, 390, 844, 0);
  проверка('без окна — прежнее место: по центру узла', близко(безОкна.y, (844 - безОкна.высота) / 2) &&
    JSON.stringify(безОкна) === JSON.stringify(ЗахватСтол.местоКарты(партия, 390, 844, 0, null)), JSON.stringify(безОкна));
}

// Окно не зависит от фазы: при любой нынешней высоте пульта место карты одно и то же (до точки).
function проверитьНезависимостьОтФазы() {
  const партия = сделатьПартию();
  const места = {};
  Object.keys(ФАЗЫ).forEach(function (фаза) {
    const окно = ЗахватСтол.замеритьОкно(сделатьДокумент(Object.assign({ высотаПульта: ФАЗЫ[фаза] }, ТЕЛЕФОН)));
    места[фаза] = окно ? ЗахватСтол.местоКарты(партия, 390, 844, 0, окно) : null;
  });
  const образец = места.расстановка;
  проверка('место в расстановке есть (ноль найденного — провал)', !!образец);
  Object.keys(ФАЗЫ).forEach(function (фаза) {
    const м = места[фаза];
    проверка('фаза «' + фаза + '» (пульт ' + ФАЗЫ[фаза] + ') — одно и то же место, что в расстановке',
      !!м && !!образец && близко(м.x, образец.x) && близко(м.y, образец.y) && близко(м.ширина, образец.ширина) && близко(м.высота, образец.высота),
      JSON.stringify([м, образец]));
  });
}

// Подсказка новичка над пультом: прежнее правило «сдвиг ровно на нужное», граница не ниже низа окна.
function проверитьПодсказкуНовичка() {
  const партия = сделатьПартию();
  const окно = ЗахватСтол.замеритьОкно(сделатьДокумент(Object.assign({ высотаПульта: ФАЗЫ.расстановка }, ТЕЛЕФОН)));
  if (!окно) { проверка('окно для подсказки замерено', false); return; }
  const без = ЗахватСтол.местоКарты(партия, 390, 844, 0, окно);
  // Верх подсказки ниже низа окна — карту не трогаем.
  const низко = ЗахватСтол.местоКарты(партия, 390, 844, 844 - 700, окно);
  проверка('подсказка ниже окна — место без изменений', JSON.stringify(низко) === JSON.stringify(без), JSON.stringify(низко));
  // Граница 560: низ карты (≈ 571) выше неё не помещается — сдвиг ровно на нужное, масштаб тот же.
  const граница = 560;
  const сдвиг = ЗахватСтол.местоКарты(партия, 390, 844, 844 - граница, окно);
  проверка('контроль: без подсказки низ карты ниже границы 560', без.y + без.высота > граница, JSON.stringify(без));
  проверка('подсказка: низ карты ровно на границе, масштаб тот же, верх не выше окна',
    близко(сдвиг.y + сдвиг.высота, граница) && близко(сдвиг.высота, без.высота) && сдвиг.y >= окно.верх - 0.5, JSON.stringify(сдвиг));
  // Граница 400: карта выше полосы [128, 400] — вписана в неё, верх = верх окна.
  const вписана = ЗахватСтол.местоКарты(партия, 390, 844, 844 - 400, окно);
  проверка('подсказка высоко — карта вписана в [верх окна, границу]', близко(вписана.y, окно.верх) &&
    вписана.y + вписана.высота <= 400.5 && вписана.ширина < без.ширина && близко(вписана.x + вписана.ширина / 2, 195), JSON.stringify(вписана));
}

// ---------- ломающие запуски на копиях ----------

function запуститьКопию(доводы) {
  const итог = spawnSync(process.execPath, [__filename].concat(доводы), { encoding: 'utf8' });
  return { код: итог.status, вывод: (итог.stdout || '') + (итог.stderr || '') };
}

function ломающие() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-окно-карты-'));
  ['захват-правила.js', 'захват-карта-вид.js', 'захват-карты.js'].forEach(function (имя) {
    fs.copyFileSync(require('./пути-проекта.js').путь(имя, КОРЕНЬ), path.join(папка, имя));
  });
  const исходник = fs.readFileSync(путьСтола, 'utf8');
  function испортить(что, чем) {
    const мест = исходник.split(что).length - 1;
    проверка('порча найдена в столе ровно один раз: ' + что.slice(0, 50), мест === 1, 'найдено мест: ' + мест);
    return исходник.replace(что, function () { return чем; });
  }
  const порчи = [
    {
      название: 'низ окна от нынешней высоты пульта, а не от наибольшего',
      файл: 'захват-стол-окно-от-пульта.js',
      текст: испортить('низ: низСодержимого - наибольший - ЗАЗОР_ОКНА_PX - верхКарты',
        "низ: д.getElementById('захват-пульт').getBoundingClientRect().top - ЗАЗОР_ОКНА_PX - верхКарты"),
      ждём: 'одно и то же место, что в расстановке'
    },
    {
      название: 'верх окна без зазора от капсул',
      файл: 'захват-стол-окно-без-зазора.js',
      текст: испортить('верх: игроки.getBoundingClientRect().bottom - верхКарты + ЗАЗОР_ОКНА_PX,',
        'верх: игроки.getBoundingClientRect().bottom - верхКарты,'),
      ждём: 'окно 390×844: верх = низ капсул + 8'
    },
    {
      название: 'местоКарты не смотрит на окно',
      файл: 'захват-стол-без-окна.js',
      текст: испортить('if (окно && окно.низ > окно.верх) return местоВОкне(', 'if (false) return местоВОкне('),
      ждём: 'карта целиком в окне'
    },
    {
      название: 'подсказка новичка: вместо сдвига на нужное — сразу вписывание',
      файл: 'захват-стол-подсказка-без-сдвига.js',
      текст: испортить('if (место.высота <= граница - окно.верх) {', 'if (false) {'),
      ждём: 'подсказка: низ карты ровно на границе'
    },
    {
      название: 'подсказка новичка: вписанная карта прижата к верху узла, а не окна',
      файл: 'захват-стол-подсказка-от-узла.js',
      текст: испортить('вписана.y = окно.верх;', 'вписана.y = 0;'),
      ждём: 'подсказка высоко — карта вписана'
    }
  ];
  порчи.forEach(function (п) {
    const куда = path.join(папка, п.файл);
    fs.writeFileSync(куда, п.текст);
    const итог = запуститьКопию(['--файл', куда]);
    проверка('ломающий запуск краснеет: ' + п.название, итог.код !== 0 && итог.вывод.indexOf(п.ждём) !== -1, 'код выхода ' + итог.код);
    console.log('  ломающий запуск «' + п.название + '»: код выхода ' + итог.код);
  });
}

// ---------- запуск ----------

проверитьРазметку();
проверитьЗамер();
проверитьМестоВОкне();
проверитьНезависимостьОтФазы();
проверитьПодсказкуНовичка();
if (!этоЛомающийЗапуск) ломающие();

console.log('Итого проверок: ' + (пройдено + провалы.length) + ', провалов: ' + провалы.length);
process.exit(провалы.length ? 1 : 0);
