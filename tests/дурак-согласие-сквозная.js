/* =====================================================================
   ДУРАК НА ТРОИХ — КОНЕЦ ПАРТИИ ПО СОГЛАСИЮ.
   СКВОЗНАЯ ПРОВЕРКА: настоящий сервер + настоящая страница index.html +
   три игрока (три независимых контекста браузера, экран 390×844).

   Правила (решения владельца и штаба):
     * за столом от 3 мест конец только по согласию: не меньше 70% живых
       людей (из трёх — все трое);
     * в дураке кто скинул все карты (вышел из игры) — не голосует и не
       мешает: если остальные уже «за», партия кончается сразу, как только
       последний несогласный выбыл;
     * ушедший из-за стола — за него бот.

   Сценарии (у каждого свой новый стол на троих):
     А — A предлагает, B и C «за»: у всех троих итог «по согласию»;
     Б — A предлагает, B «за», C «Играть дальше»: голосование снято, партия
         идёт, окна нет ни у кого. Потом B предлагает, A «за», C молчит
         до срока: то же самое;
     В — A и B «за», C скидывает последние карты (говорит «Бито» и выходит
         из игры): партия кончается сразу, не дожидаясь срока.
         Раздачу «у C пустая рука, осталось сказать „Бито“» готовит сам
         тестовый сервер (как случай з в tests/дурак-согласие-сервер.js),
         а «Бито», голоса и итог — настоящие нажатия на страницах;
     Г — в консоли трёх страниц нет ошибок.

   Как устроено.
     * Свой сервер комнат — отдельный процесс (эта же программа с доводом
       --сервер) на порту 8151; страницы отдаёт tests/локальный-сервер.js
       на порту 8152. Боевой 8790 и 8765 не трогаем. Оба гасятся по PID.
     * Каждый шаг — «что ждали / что увидели». Красный шаг не прерывает
       прогон (в ломающем режиме — стоп на первом).

   Запуск (перед браузерным — отдельной командой «node штаб/браузер-занят.js»):
       node tests/дурак-согласие-сквозная.js
       node tests/дурак-согласие-сквозная.js --сломать <папка вне проекта>
   Служебные доводы (ставит сама проверка): --прогон, --сервер, --корень,
   --порт-комнат, --порт-файлов, --без-двери, --стоп, --снимки, --сценарий.

   Ломающий режим (--сломать <папка>): на КОПИЯХ проекта в этой папке
     1) сервер без вызова пересчёта голосования после выбывания в
        сделатьХод — сценарий В краснеет (партия висит до срока);
     2) пересчёт не считает «скинул карты» выбывшим — сценарий В краснеет;
     3) дверь голосования для дурака закрыта — шаг А1 краснеет;
     4) общее/js/лист-ещё.js, где плашка голосования не показывается, — А2.
   Файлы проекта не трогаются. Итог: «Поломок: N, покраснело: N».
   ===================================================================== */
