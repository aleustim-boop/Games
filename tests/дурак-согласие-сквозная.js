function скопироватьПроект(папка) {
  for (const часть of ['server', ...require('./пути-проекта.js').папкиКода()]) {
    const откуда = path.join(ПРОЕКТ, часть);
    if (!fs.existsSync(откуда)) continue;
    fs.cpSync(откуда, path.join(папка, часть), {
      recursive: true,
      filter: ф => { const имя = path.basename(ф); return имя !== 'данные' && имя !== 'node_modules'; }
    });
  }
  for (const файл of fs.readdirSync(ПРОЕКТ)) {
    if (файл.endsWith('.html') || файл.endsWith('.css')) fs.copyFileSync(path.join(ПРОЕКТ, файл), path.join(папка, файл));
  }
}

/* Файл может лежать с концами строк Windows: многострочный кусок ищем в том же виде. */
const какВФайле = (текст, кусок) => текст.indexOf('\r\n') !== -1 ? кусок.replace(/\r?\n/g, '\r\n') : кусок;

function заменитьРовноОдин(папка, относительныйПуть, было, стало) {
  const файл = path.join(папка, относительныйПуть);
  const текст = fs.readFileSync(файл, 'utf8');
  const части = текст.split(какВФайле(текст, было));
  if (части.length !== 2) throw new Error('в копии ' + относительныйПуть + ' место поломки нашлось ' + (части.length - 1) + ' раз(а), нужно ровно один');
  fs.writeFileSync(файл, части.join(какВФайле(текст, стало)), 'utf8');
}

