'use strict';

/* Проверка без браузера: лобби шахмат и шаг «Игра онлайн» сделаны как у дурака
   (владелец 02.10: «все онлайн игры в одном стиле, эталон — дурак»).
   Читает разметку и код как текст.

   Запуск:  node tests/шахматы-лобби-как-дурак.js [путь-к-шахматы.html]
   Путь нужен для «красного» запуска: проверка на КОПИИ страницы, где
   поломку вернули (серия вместо места и т.п.), обязана упасть. Настоящий
   файл портить нельзя.

   Ноль найденных узлов — провал, а не пропуск: каждая проверка сначала
   требует, чтобы нужный узел нашёлся. */

const fs = require('fs');
const path = require('path');

const корень = path.join(__dirname, '..');
const путьHtml = process.argv[2] ? path.resolve(process.argv[2]) : path.join(корень, 'шахматы.html');
const html = fs.readFileSync(путьHtml, 'utf8');
const код = fs.readFileSync(path.join(корень, 'js', 'шахматы-лобби.js'), 'utf8');
const стили = fs.readFileSync(path.join(корень, 'style-шахматы.css'), 'utf8');

let провалов = 0;
let всего = 0;
function проверить(условие, слова) {
  всего++;
  if (!условие) провалов++;
  console.log((условие ? '  ок      ' : '  ПРОВАЛ  ') + слова);
}

/** Кусок текста от начала открывающего тега до закрывающего (без вложенных одноимённых). */
function кусок(текст, начало, конец) {
  const от = текст.indexOf(начало);
  if (от === -1) return '';
  const до = текст.indexOf(конец, от);
  return до === -1 ? '' : текст.slice(от, до + конец.length);
}

console.log('Страница: ' + путьHtml);

// 1. Карточка профиля — место в рейтинге, не серия побед.
console.log('\n1. Карточка профиля');
const профиль = кусок(html, '<button id="лобби-профиль"', '</button>');
проверить(профиль.length > 0, 'карточка «лобби-профиль» найдена');
проверить(/id="лобби-место"/.test(профиль), 'в карточке есть узел «лобби-место»');
проверить(/id="лобби-рейтинг"[^>]*карточка-профиля__рейтинг/.test(профиль), 'строка рейтинга «лобби-рейтинг» с классом карточка-профиля__рейтинг');
проверить(/id="лобби-аватар"/.test(профиль), 'аватар «лобби-аватар», как у дурака');
проверить(!/лобби-серия-текст/.test(html), 'узла серии побед «лобби-серия-текст» нет нигде в странице');
проверить(!/лобби-серия-текст/.test(код) && !/строкаСерии/.test(код), 'в js/шахматы-лобби.js серии побед нет');
проверить(/ЭкранРейтинга\.моёМесто\('шахматы'\)/.test(код), 'место берётся тем же ходом, что у дурака: ЭкранРейтинга.моёМесто(\'шахматы\')');

// 2. Картинка с подписью той же высоты.
console.log('\n2. Картинка-гнездо');
const картинка = кусок(html, '<figure class="лобби__картинка">', '</figure>');
проверить(картинка.length > 0, 'figure.лобби__картинка найдена');
const подпись = /<figcaption class="лобби__подпись">([^<]+)<\/figcaption>/.exec(картинка);
проверить(Boolean(подпись) && подпись[1].trim().length > 0, 'у картинки есть подпись figcaption.лобби__подпись' + (подпись ? ' («' + подпись[1].trim() + '»)' : ''));
проверить(/figure\.лобби__картинка:has\(img\[src\*="лобби-2026"\]\)\s*\{\s*aspect-ratio:\s*16\s*\/\s*10/.test(стили), 'рамка 16:10 как у дурака (style-шахматы.css), а не панорама');
проверить(!/aspect-ratio:\s*876\s*\/\s*204/.test(стили), 'старой узкой панорамы 876/204 в style-шахматы.css нет');

// 3. Карточки входов.
console.log('\n3. Карточки входов');
const боты = кусок(html, '<button id="лобби-боты"', '</button>');
проверить(боты.length > 0, 'карточка «лобби-боты» найдена');
проверить(/карточка-входа__название">Играть с ботами</.test(боты), 'подпись карточки — «Играть с ботами»');
проверить(!/Играть с ботом</.test(боты), 'старой подписи «Играть с ботом» нет');
const вдвоём = кусок(html, '<button id="лобби-вдвоём"', '</button>');
проверить(/Вдвоём на этом устройстве/.test(вдвоём), 'карточка «Вдвоём на этом устройстве» осталась (просьба владельца 25.09)');

// 4. Шаг «Игра онлайн»: верхняя строка «‹ ⋯» и «Назад» на список столов.
console.log('\n4. Шаг «Игра онлайн»');
const шаг = кусок(html, '<section id="экран-лобби-онлайн"', '</section>');
проверить(шаг.length > 0, 'секция «экран-лобби-онлайн» найдена');
проверить(/class="верх-игры"/.test(шаг), 'у шага есть верхняя строка «верх-игры»');
проверить(/id="кнопка-лобби-онлайн-назад"/.test(шаг), 'в верхней строке есть «‹»');
проверить(/id="кнопка-лобби-онлайн-ещё"[^>]*aria-label="Ещё"/.test(шаг), 'в верхней строке есть «⋯»');
проверить(/id="лобби-онлайн-время-нет"/.test(шаг) && /id="лобби-онлайн-создать"/.test(шаг), 'выбор времени и «Создать игру» на месте');
проверить(/id="лобби-онлайн-назад"/.test(шаг), 'внизу есть кнопка «Назад»');

const функцияНазад = кусок(код, 'function вернутьсяНаСписокСтолов()', '\n    }');
проверить(/ЭкранОткрытыхСтолов/.test(функцияНазад) && /\.вернуться\(\)/.test(функцияНазад), 'вернутьсяНаСписокСтолов зовёт ЭкранОткрытыхСтолов.вернуться()');
const цикл = кусок(код, "for (const id of ['лобби-онлайн-назад', 'кнопка-лобби-онлайн-назад'])", '}\n');
проверить(цикл.length > 0, 'цикл привязки «Назад» шага найден');
проверить(/вернутьсяНаСписокСтолов/.test(цикл) && !/показатьЛобби/.test(цикл), '«Назад» и «‹» шага ведут на список столов, а не в лобби');
проверить(/кнопка-лобби-онлайн-ещё[\s\S]{0,300}нажать\('кнопка-игра-ещё'\)/.test(код), '«⋯» шага нажимает общий лист «⋯» доски');

console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
process.exit(провалов === 0 ? 0 : 1);
