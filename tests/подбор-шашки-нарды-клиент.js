/* =====================================================================
   «НАЙТИ ИГРУ» У ШАШЕК И НАРД — КЛИЕНТСКАЯ ЧАСТЬ, БЕЗ БРАУЗЕРА.

   Проверяет ровно два клиентских шага плана штаб/план-подбор-шашки-нарды.md:

   А) js/сеть.js, встатьВОчередь(): тело запроса «/подбор» несёт поле «игра»,
      равное игре ЭТОЙ страницы (window.ИграСтраницы) — «шашки», «нарды»,
      «дурак» явно и «дурак» по умолчанию (старая страница ничего не сказала).
      Файл поднимается в песочнице (vm) целиком, как в tests/адрес-сервера-
      по-умолчанию.js; fetch подделан и только ЗАПОМИНАЕТ тело запроса, ответа
      не даёт — обещание висит вечно, нам хватает самого факта запроса.

   Б) js/открытые-столы.js: кнопка «Найти игру» (открытые-столы-подбор)
      видна у дурака, шашек и нард — и НЕ видна у деберца, домино, катана,
      морского боя (там свой мастер настроек, window.НастройкиЭкранаОнлайн,
      автоподбора не было и не появилось). Экран строится вызовом настоящей
      двери window.ЭкранОткрытыхСтолов.открыть() в поддельном document —
      второй копии разметки/id здесь не заводим, id и подпись кнопки читаем
      прямо из исходника (тем же приёмом, что tests/найти-игру-в-браузере.js).

   Запуск:
       node tests/подбор-шашки-нарды-клиент.js
   Свои копии файлов (ломающий прогон отдельно портит КОПИЮ во временной
   папке, не файл проекта):
       node tests/подбор-шашки-нарды-клиент.js --сеть=<путь> --столы=<путь>

   Ломающий запуск (готовит две испорченные копии сам, во временной папке
   ОС, ничего в проекте не трогает) — проверка обязана покраснеть:
       node tests/подбор-шашки-нарды-клиент.js --сломать

   Выход 0 — провалов нет, 1 — есть.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { поднять, сделатьДокумент, сделатьПамять } = require('./поддельный-браузер.js');

const КОРЕНЬ = path.join(__dirname, '..');

function довод(имя) {
  const найден = process.argv.find(function (д) { return д.indexOf('--' + имя + '=') === 0; });
  return найден ? найден.slice(имя.length + 3) : '';
}

const СЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;

const проверки = [];
function проверить(условие, текст) {
  проверки.push({ ок: Boolean(условие), текст: текст });
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + текст);
}
function сказать(текст) { console.log('  ' + текст); }

/* ---------------------------------------------------------------------
   Готовим ломающие копии сами — во временной папке ОС, файл проекта
   не трогаем ни на секунду (правило штаба).
   --------------------------------------------------------------------- */
function приготовитьЛомающиеКопии() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'подбор-шашки-нарды-сломать-'));

  const исходникСети = fs.readFileSync(path.join(КОРЕНЬ, 'js', 'сеть.js'), 'utf8');
  /* Та же строка «тело.игра = ИГРА_ЭТОЙ_СТРАНИЦЫ;» есть в файле ДВАЖДЫ —
     ещё и в телоСоздания() для двери «/создать». Ломаем именно встатьВОчередь,
     поэтому берём соседнюю строку («метка: имяВкладки») как уникальный якорь. */
  const якорь = /метка: имяВкладки \};\r?\n\s*тело\.игра = ИГРА_ЭТОЙ_СТРАНИЦЫ;/;
  if (!якорь.test(исходникСети)) {
    throw new Error('не нашёл в js/сеть.js строку «тело.игра = ИГРА_ЭТОЙ_СТРАНИЦЫ;» сразу после «метка: ' +
      'имяВкладки };» — ломающий приём устарел, поправь его');
  }
  const сетьБезИгры = исходникСети.replace(якорь,
    'метка: имяВкладки };\n      /* тело.игра = ИГРА_ЭТОЙ_СТРАНИЦЫ; — вырезано нарочно ломающим прогоном */');
  const путьСети = path.join(папка, 'сеть-без-игры.js');
  fs.writeFileSync(путьСети, сетьБезИгры, 'utf8');

  const исходникСтолов = fs.readFileSync(path.join(КОРЕНЬ, 'js', 'открытые-столы.js'), 'utf8');
  const строкаУсловия = 'if (показатьКнопкуПодбора()) {';
  if (исходникСтолов.indexOf(строкаУсловия) === -1) {
    throw new Error('не нашёл в js/открытые-столы.js строку «' + строкаУсловия + '» — ломающий приём устарел, поправь его');
  }
  const столыСоСтарымУсловием = исходникСтолов.replace(строкаУсловия,
    'if (дурак && !window.НастройкиЭкранаОнлайн) {   /* старое условие — вернуло ломающим прогоном */');
  const путьСтолов = path.join(папка, 'открытые-столы-старое-условие.js');
  fs.writeFileSync(путьСтолов, столыСоСтарымУсловием, 'utf8');

  return { папка: папка, путьСети: путьСети, путьСтолов: путьСтолов };
}

/* ---------------------------------------------------------------------
   А. js/сеть.js — тело запроса «/подбор» несёт игру страницы
   --------------------------------------------------------------------- */

/** Подобие setImmediate-паузы: дать microtask- и macrotask-очередям
    прокрутиться, пока встатьВОчередь дойдёт от решитьСпорАдресов()
    до самого fetch (та же цепочка .then, что и в живом браузере). */
function подождать() {
  return new Promise(function (готово) { setTimeout(готово, 0); });
}

function подделанныйFetch(запросы) {
  return function (адрес, настройки) {
    let тело = null;
    try { тело = JSON.parse((настройки && настройки.body) || '{}'); } catch (сбой) { тело = null; }
    запросы.push({ адрес: String(адрес), тело: тело });
    return new Promise(function () {});   // ответа не будет — нам хватает самого запроса
  };
}

/** Поднять сеть.js с заданной window.ИграСтраницы (пусто — страница
    вообще ничего не сказала, как старый кэш) и встать в очередь один раз. */
async function телоПодбораДля(исходникСети, играСтраницы) {
  const запросы = [];
  const текст = играСтраницы
    ? "window.ИграСтраницы = '" + играСтраницы + "';\n" + исходникСети
    : исходникСети;
  const рез = поднять(текст, {
    документ: сделатьДокумент(),
    память: сделатьПамять(false),
    telegram: { initData: 'user=%7B%22id%22%3A1%2C%22first_name%22%3A%22Тест%22%7D&hash=abc' },
    fetch: подделанныйFetch(запросы),
    имяФайла: 'js/сеть.js'
  });
  if (!рез.окно.Сеть || typeof рез.окно.Сеть.встатьВОчередь !== 'function') {
    throw new Error('window.Сеть.встатьВОчередь не появилась (игра страницы: «' + (играСтраницы || '(пусто)') + '»)');
  }
  рез.окно.Сеть.встатьВОчередь();   // без await — обещание висит вечно (fetch не отвечает)
  await подождать();
  await подождать();
  const запросПодбора = запросы.find(function (з) { return з.адрес.indexOf('/подбор') !== -1; });
  return { запросПодбора: запросПодбора, всеЗапросы: запросы };
}

async function проверитьСетьИгру(исходникСети, играСтраницы, ждём) {
  const подпись = играСтраницы ? 'window.ИграСтраницы=\'' + играСтраницы + '\'' : 'window.ИграСтраницы не задана (старая страница)';
  let итог;
  try {
    итог = await телоПодбораДля(исходникСети, играСтраницы);
  } catch (сбой) {
    проверить(false, 'А ' + подпись + ': упало — ' + (сбой && сбой.message || сбой));
    return;
  }
  if (!итог.запросПодбора) {
    проверить(false, 'А ' + подпись + ': запрос «/подбор» не улетел (запросов всего: ' + итог.всеЗапросы.length + ')');
    return;
  }
  const игра = итог.запросПодбора.тело && итог.запросПодбора.тело.игра;
  проверить(игра === ждём, 'А ' + подпись + ': тело «/подбор» несёт игру «' + ждём +
    '» (получили ' + JSON.stringify(игра) + ')');
}

/* ---------------------------------------------------------------------
   Б. js/открытые-столы.js — кнопка «Найти игру»
   --------------------------------------------------------------------- */

function создатьИзвлекатель(текст, имяФайла) {
  return function извлечь(регулярка, откуда) {
    const найдено = текст.match(регулярка);
    if (!найдено) throw new Error('не нашёл в ' + имяФайла + ': ' + откуда);
    return найдено[1];
  };
}

/** Построить экран «Играть онлайн» настоящей дверью и вернуть узел кнопки
    «Найти игру» (или null — её честно нет). ЭКРАН должен появиться в любом
    случае: если нет и его, проверка обязана провалиться отдельной сверкой,
    а не тихо решить, что кнопки «поэтому» тоже нет. */
async function построитьЭкранСтолов(исходникСтолов, настройка) {
  const документ = сделатьДокумент();
  if (настройка.дуракУзел) {
    документ.body.appendChild(документ.узел('div', { id: 'лобби-играть-онлайн' }));
  }
  const рез = поднять(исходникСтолов, {
    документ: документ,
    fetch: function () { return new Promise(function () {}); },
    имяФайла: 'js/открытые-столы.js'
  });
  if (настройка.играСтраницы) рез.окно.ИграСтраницы = настройка.играСтраницы;
  if (настройка.мастерНастроек) рез.окно.НастройкиЭкранаОнлайн = {};
  if (!рез.окно.ЭкранОткрытыхСтолов || typeof рез.окно.ЭкранОткрытыхСтолов.открыть !== 'function') {
    throw new Error('window.ЭкранОткрытыхСтолов.открыть не появилась');
  }
  рез.окно.ЭкранОткрытыхСтолов.открыть();
  await подождать();
  const экран = документ.getElementById('экран-открытые-столы');
  return { экран: экран, документ: документ };
}

async function проверитьКнопку(исходникСтолов, идКнопки, текстКнопки, имя, настройка, ждёмКнопку) {
  let итог;
  try {
    итог = await построитьЭкранСтолов(исходникСтолов, настройка);
  } catch (сбой) {
    проверить(false, 'Б ' + имя + ': упало — ' + (сбой && сбой.message || сбой));
    return;
  }
  if (!итог.экран) {
    проверить(false, 'Б ' + имя + ': экран «Играть онлайн» вообще не построился');
    return;
  }
  const кнопка = итог.документ.getElementById(идКнопки);
  if (ждёмКнопку) {
    проверить(Boolean(кнопка), 'Б ' + имя + ': кнопка «Найти игру» видна');
    if (кнопка) {
      проверить(кнопка.textContent === текстКнопки,
        'Б ' + имя + ': подпись кнопки «' + текстКнопки + '» (получили «' + кнопка.textContent + '»)');
    }
  } else {
    проверить(!кнопка, 'Б ' + имя + ': кнопки «Найти игру» нет (как и сейчас)');
  }
}

/* ---------------------------------------------------------------------
   Главное
   --------------------------------------------------------------------- */

async function главное() {
  let ломающиеКопии = null;
  let путьСети = довод('сеть');
  let путьСтолов = довод('столы');

  if (СЛОМАТЬ) {
    ломающиеКопии = приготовитьЛомающиеКопии();
    console.log('*** ЛОМАЮЩИЙ ЗАПУСК: во временной папке ' + ломающиеКопии.папка +
      ' — копия сеть.js без «тело.игра = ИГРА_ЭТОЙ_СТРАНИЦЫ;» и копия открытые-столы.js со старым ' +
      'условием кнопки («дурак && !НастройкиЭкранаОнлайн»). Проверка обязана покраснеть. ***');
    if (!путьСети) путьСети = ломающиеКопии.путьСети;
    if (!путьСтолов) путьСтолов = ломающиеКопии.путьСтолов;
  }

  if (путьСети) сказать('сеть.js берём из: ' + путьСети);
  if (путьСтолов) сказать('открытые-столы.js берём из: ' + путьСтолов);

  try {
    const исходникСети = fs.readFileSync(путьСети || path.join(КОРЕНЬ, 'js', 'сеть.js'), 'utf8');
    const исходникСтолов = fs.readFileSync(путьСтолов || path.join(КОРЕНЬ, 'js', 'открытые-столы.js'), 'utf8');

    console.log('\n=== А. js/сеть.js: тело «/подбор» несёт игру страницы ===');
    await проверитьСетьИгру(исходникСети, 'шашки', 'шашки');
    await проверитьСетьИгру(исходникСети, 'нарды', 'нарды');
    await проверитьСетьИгру(исходникСети, 'дурак', 'дурак');
    await проверитьСетьИгру(исходникСети, '', 'дурак');   // старая страница ничего не сказала

    console.log('\n=== Б. js/открытые-столы.js: кнопка «Найти игру» ===');
    const извлечь = создатьИзвлекатель(исходникСтолов, 'js/открытые-столы.js');
    const КНОПКА_ПОДБОР = извлечь(/const КНОПКА_ПОДБОР = '([^']+)';/, 'id кнопки «Найти игру»');
    const ТЕКСТ_ПОДБОР = извлечь(/кнопкаЭл\(КНОПКА_ПОДБОР,\s*'([^']+)'/, 'подпись кнопки «Найти игру»');
    сказать('id кнопки: «' + КНОПКА_ПОДБОР + '», подпись: «' + ТЕКСТ_ПОДБОР + '»');

    await проверитьКнопку(исходникСтолов, КНОПКА_ПОДБОР, ТЕКСТ_ПОДБОР, 'дурак',
      { дуракУзел: true }, true);
    await проверитьКнопку(исходникСтолов, КНОПКА_ПОДБОР, ТЕКСТ_ПОДБОР, 'шашки',
      { играСтраницы: 'шашки' }, true);
    await проверитьКнопку(исходникСтолов, КНОПКА_ПОДБОР, ТЕКСТ_ПОДБОР, 'нарды',
      { играСтраницы: 'нарды' }, true);
    await проверитьКнопку(исходникСтолов, КНОПКА_ПОДБОР, ТЕКСТ_ПОДБОР, 'деберц',
      { играСтраницы: 'деберц', мастерНастроек: true }, false);
    await проверитьКнопку(исходникСтолов, КНОПКА_ПОДБОР, ТЕКСТ_ПОДБОР, 'домино',
      { играСтраницы: 'домино', мастерНастроек: true }, false);
    await проверитьКнопку(исходникСтолов, КНОПКА_ПОДБОР, ТЕКСТ_ПОДБОР, 'катан',
      { играСтраницы: 'катан', мастерНастроек: true }, false);
    await проверитьКнопку(исходникСтолов, КНОПКА_ПОДБОР, ТЕКСТ_ПОДБОР, 'морской бой',
      { играСтраницы: 'морской-бой', мастерНастроек: true }, false);
  } finally {
    // Уборка — всегда, даже если проверка выше упала посреди себя:
    // временная папка ломающего прогона не должна остаться мусором.
    if (ломающиеКопии) {
      try { fs.rmSync(ломающиеКопии.папка, { recursive: true, force: true }); } catch (сбой) { /* не страшно */ }
    }
  }

  const провалы = проверки.filter(function (п) { return !п.ок; });
  console.log('\nИтого проверок: ' + проверки.length + ', провалов: ' + провалы.length);
  process.exit(провалы.length ? 1 : 0);
}

главное().catch(function (сбой) {
  console.error('Проверка упала: ' + (сбой && сбой.stack || сбой));
  process.exit(2);
});
