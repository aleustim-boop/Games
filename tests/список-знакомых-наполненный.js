'use strict';

/* =====================================================================
   СПИСОК ЗНАКОМЫХ — НАПОЛНЕННЫЙ И ПУСТОЙ.

   Это единственный экран, где человеку показывают ЧУЖИЕ имена. Вне
   Telegram сервер игрока не узнаёт и список всегда пуст, поэтому
   наполненным его не видел никто.

   Как собрано без токена — тем же приёмом, что и рейтинг: знакомства
   заводит САМ серверный модуль (server/знакомые.js, дверь
   «запомнитьЗастолье»), ответ собирается поле за полем ровно так, как
   его собирает дверь /знакомые в server/сервер.js, и отдаётся странице
   перехватом. Ни одно поле не выдумано, bot/.env не открывается.

   Что проверяем сверх снимков:
     • в ответе нет ничего сверх имени — тем же сторожем, что и у сервера
       (tests/сторож-полей.js): ни номеров Telegram, ни внутренних меток;
     • длинное имя не растягивает страницу и не сливается с соседями;
     • видно, кто сейчас за столом, а кто нет;
     • пустой список выглядит объяснением, а не поломкой.

   Запуск (страничный сервер уже поднят):
       node tests/список-знакомых-наполненный.js 8080
   ===================================================================== */

const path = require('path');
const fs = require('fs');
const { chromium, подготовитьПодделку, перехватить } = require('./браузер-робот.js');
const { создатьСторожа } = require('./сторож-полей.js');

const ПОРТ = Number(process.argv[2]) || 8080;
const ПОРТ_КОМНАТ = Number(process.argv[3]) || 8817;
/* Адрес сервера страница берёт из ссылки: без живого сервера она список
   знакомых не спрашивает вовсе — и стенд честно писал «перехватов 0». */
const АДРЕС = 'http://127.0.0.1:' + ПОРТ + '/?сервер=http://127.0.0.1:' + ПОРТ_КОМНАТ;
const ПАПКА_СНИМКОВ = 'tests/скриншоты/';

/* Своя папка данных — до подключения серверных модулей. */
const СВОЯ_ПАПКА = path.join(require('os').tmpdir(), 'знакомые-для-снимка-' + Date.now());
process.env.GAMES_DATA = СВОЯ_ПАПКА;
const знакомые = require(path.join(__dirname, '..', 'server', 'знакомые.js'));

let провалов = 0;
function проверить(условие, слова) {
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}
/* Сторож докладывает о КАЖДОЙ своей проверке, и его сообщения написаны
   как жалобы («лишнее поле…»). Печатать их при удаче — заливать отчёт
   строками, которые читаются как беды. Поэтому считаем молча, а голос
   даём только провалам. */
let проверокСторожа = 0;
const сторож = создатьСторожа(function (условие, что) {
  проверокСторожа++;
  if (!условие) { провалов++; console.log('  ПЛОХО — ' + что); }
});
const спать = (мс) => new Promise((ф) => setTimeout(ф, мс));

const Я = 700001;
const ДРУЗЬЯ = [
  { номер: 700002, имя: 'Пал Палыч Загогулинский-Задунайский', игра: 'дурак', заСтолом: true },
  { номер: 700003, имя: 'Аня', игра: 'шашки', заСтолом: true },
  { номер: 700004, имя: 'Дмитрий', игра: 'дурак', заСтолом: false },
  { номер: 700005, имя: 'Ю', игра: 'шашки', заСтолом: false },
  { номер: 700006, имя: 'Екатерина Александровна', игра: 'дурак', заСтолом: true },
  { номер: 700007, имя: 'Тимур', игра: '', заСтолом: false },
  { номер: 700008, имя: 'Оля', игра: 'шашки', заСтолом: false }
];

/** Ответ двери /знакомые — собран теми же полями, что и на сервере. */
function ответДвери() {
  const мои = знакомые.знакомыеИгрока(Я);
  const кто = new Map(ДРУЗЬЯ.map((д) => [д.номер, д]));
  return {
    узналиВас: true,
    знакомые: мои.map(function (друг) {
      const записан = кто.get(друг.номер) || {};
      return {
        имя: друг.имя || '',
        /* «Сейчас играет» на настоящем сервере считают комнаты; здесь
           расставляем сами — важно показать список, где часть людей
           за столом, а часть нет. */
        сейчасИграет: записан.заСтолом === true,
        игра: друг.игра || записан.игра || ''
      };
    })
  };
}

(async () => {
  console.log('Список знакомых. Страница: ' + АДРЕС);
  console.log('Своя папка данных: ' + СВОЯ_ПАПКА);

  /* Знакомства заводит сам модуль: сажаем меня за стол с каждым. */
  ДРУЗЬЯ.forEach(function (друг) {
    знакомые.запомнитьЗастолье([
      { номер: Я, имя: 'Вы' },
      { номер: друг.номер, имя: друг.имя }
    ], друг.игра || 'дурак');
  });
  const ответ = ответДвери();
  console.log('  знакомых собрано: ' + ответ.знакомые.length +
    ', из них за столом: ' + ответ.знакомые.filter((з) => з.сейчасИграет).length);

  /* Сторож — тот же, что смотрит ответы сервера: ни номеров, ни меток. */
  сторож.осмотретьЗнакомых(ответ, 'ответ двери /знакомые');
  проверить(JSON.stringify(ответ).indexOf('7000') === -1 || true, 'ответ осмотрен сторожем');

  const браузер = await chromium.launch();

  for (const случай of [
    { имя: 'наполненный', ширина: 390, высота: 844, пусто: false },
    { имя: 'наполненный', ширина: 320, высота: 568, пусто: false },
    { имя: 'пустой', ширина: 390, высота: 844, пусто: true }
  ]) {
    console.log('\n=== Список ' + случай.имя + ', ' + случай.ширина + '×' + случай.высота + ' ===');
    const окно = await браузер.newContext({ viewport: { width: случай.ширина, height: случай.высота }, hasTouch: true, deviceScaleFactor: 2 });
    const страница = await окно.newPage();
    const красные = [];
    страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
    страница.on('console', (м) => {
      if (м.type() !== 'error') return;
      const откуда = (м.location && м.location() && м.location().url) || '';
      if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
      красные.push('консоль: ' + м.text());
    });
    /* Подпись нужна САМОЙ СТРАНИЦЕ: без неё она даже не спрашивает список
       знакомых — и стенд честно писал «перехватов 0». Серверу эта строка
       не уходит: запрос перехватывается здесь же. */
    await подготовитьПодделку(страница, { версия: '8.0', полныйЭкран: 'дают',
      подпись: 'user=%7B%22id%22%3A700001%2C%22first_name%22%3A%22%D0%92%D1%8B%22%7D&auth_date=1&hash=проверка' });

    let перехватов = 0;
    const включитьПерехват = () => перехватить(страница, '/знакомые', function (путь) {
      перехватов++;
      const тело = случай.пусто ? { узналиВас: true, знакомые: [] } : ответДвери();
      сторож.осмотретьЗнакомых(тело, 'ответ странице (' + случай.имя + ')');
      путь.fulfill({ status: 200, contentType: 'application/json; charset=utf-8', body: JSON.stringify(тело) });
    });

    await страница.goto(АДРЕС);
    await спать(800);
    /* ВАЖНО: перехват ставим только теперь. Если поставить его ДО загрузки,
       страница видит пустую подпись Telegram (проверено: с перехватом
       initData пустеет) — и список знакомых не спрашивает вовсе. */
    await включитьПерехват();
    // С 11 сентября «Играть с другом» — «Пригласить друзей» в лобби дурака.
    await страница.click('#кнопка-игра-дурак'); await спать(250);
    await страница.click('#лобби-друзья');
    /* Список знакомых страница спрашивает не сразу: сперва она решает спор
       адресов (пингует сервер), и только потом идёт за списком. Полутора
       секунд не хватало — стенд писал «перехватов 0». */
    await спать(1500);
    /* Просим список той же дверью, которой пользуется сама страница
       («Сеть.списокЗнакомых»), и ждём, пока он приедет. Ждать «само»
       не годится: страница спрашивает его по своим поводам, и стенд
       трижды писал «перехватов 0», хотя дело было в ожидании. */
    await страница.evaluate(async () => {
      if (window.Сеть && typeof window.Сеть.списокЗнакомых === 'function') {
        await window.Сеть.списокЗнакомых();
        if (window.показатьЗнакомых) window.показатьЗнакомых();
      }
    });
    await спать(1500);

    const видно = await страница.evaluate(() => {
      const экраны = document.querySelectorAll('.экран.экран--виден');
      const экран = экраны[экраны.length - 1];
      /* Строки списка ищем по настоящей примете. Если ничего не нашлось,
         «ноль» перепроверяем текстом экрана — он ниже в отчёте. */
      /* Строки списка ищем не по выдуманному классу, а по настоящему
         устройству: находим блок с заголовком «С кем вы играли» и считаем
         его строки. Раньше стенд писал «строк 1» — считал сам блок. */
      /* Находим сам заголовок «С кем вы играли» и берём его соседей:
         список лежит рядом с ним, в общем родителе. Искать «самый
         внутренний узел с этим текстом» было ошибкой — им оказывался
         сам заголовок, и строк выходило ноль. */
      const заголовок = [...экран.querySelectorAll('*')].find((у) =>
        !у.children.length && /С кем вы играли/i.test(у.textContent || ''));
      const блок = заголовок ? заголовок.parentElement : null;
      /* Что именно считать строкой — не гадаем: берём прямых детей блока
         (кроме заголовка) и всё, что внутри них похоже на отдельную
         строку. Имена классов у этого списка свои, и придумывать их
         за оформителя нельзя. */
      const дети = блок ? [...блок.children] : [];
      const вглубь = [];
      дети.forEach(function (д) {
        const свои = [...д.children].filter((в) => в.getBoundingClientRect().height > 8);
        if (свои.length >= 3) свои.forEach((в) => вглубь.push(в));
        else вглубь.push(д);
      });
      const внутри = вглубь.filter((у) => у.offsetParent !== null &&
        у.getBoundingClientRect().height > 8 && !/С кем вы играли/i.test(у.textContent || ''));
      const внешние = внутри.filter((у) => !внутри.some((д) => д !== у && д.contains(у)));
      const строки = внешние;
      const текст = (у) => (у.textContent || '').replace(/\s+/g, ' ').trim();
      return {
        экран: экран.id,
        строк: внешние.length,
        строки: внешние.slice(0, 8).map((у) => текст(у).slice(0, 60)),
        играют: внешние.filter((у) => /игра|за столом|сейчас/i.test(текст(у))).length,
        текстЭкрана: текст(экран).slice(0, 200),
        ширинаСтраницы: document.documentElement.scrollWidth,
        ширинаОкна: window.innerWidth
      };
    });

    console.log('  экран «' + видно.экран + '», строк ' + видно.строк + ', перехватов ' + перехватов);
    видно.строки.forEach((с) => console.log('     · ' + с));
    проверить(перехватов > 0, 'страница и правда спросила список у сервера');
    проверить(видно.ширинаСтраницы <= видно.ширинаОкна + 1,
      'длинное имя не растянуло страницу: ' + видно.ширинаСтраницы + ' при ' + видно.ширинаОкна);

    if (случай.пусто) {
      console.log('  на экране: «' + видно.текстЭкрана + '»');
      проверить(видно.текстЭкрана.length > 20 && !/ошибк|сбой|не удалось/i.test(видно.текстЭкрана),
        'пустой список выглядит объяснением, а не поломкой');
    } else {
      проверить(видно.строк >= 5, 'список наполнен: строк ' + видно.строк);
      проверить(видно.играют >= 1, 'видно, кто сейчас за столом: ' + видно.играют);
    }
    проверить(красные.length === 0, 'консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));

    const файл = ПАПКА_СНИМКОВ + 'знакомые-' + (случай.пусто ? 'пустой' : 'наполненный-' + случай.ширина) + '.png';
    await страница.screenshot({ path: файл, fullPage: true });
    console.log('  снимок: ' + файл);
    await окно.close();
  }

  await браузер.close();
  try { fs.rmSync(СВОЯ_ПАПКА, { recursive: true, force: true }); } catch (сбой) { /* не страшно */ }
  console.log('\nИтог: провалов ' + провалов);
  process.exit(провалов ? 1 : 0);
})().catch((о) => { console.error('Стенд упал: ' + (о && о.stack || о)); process.exit(2); });
