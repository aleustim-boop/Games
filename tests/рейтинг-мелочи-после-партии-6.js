/** Проверить положение разрыва (или его отсутствие) перед первой строкой
    списка: ищем шапку «МЕСТО/ИГРОК/ОЧКИ», следующий узел таблицы — либо
    сама первая строка (ожидаетсяРазрыв=false), либо разрыв «⋯», а за ним
    первая строка (ожидаетсяРазрыв=true). */
function проверитьРазрывПередПервой(таблица, ожидаетсяРазрыв, местоПервой, имяСценария) {
  const дети = таблица.children;
  let индексШапки = -1;
  for (let i = 0; i < дети.length; i++) {
    if (дети[i].classList && дети[i].classList.contains('рейтинг-строка--шапка')) { индексШапки = i; break; }
  }
  проверить(имяСценария + ': шапка списка нашлась в таблице', индексШапки !== -1);
  const первыйУзелСписка = индексШапки !== -1 ? дети[индексШапки + 1] : null;
  проверить(имяСценария + ': первый узел списка после шапки есть', Boolean(первыйУзелСписка));
  if (!первыйУзелСписка) return;
  const этоРазрыв = первыйУзелСписка.classList.contains('рейтинг-строка--разрыв');
  проверить(
    имяСценария + (ожидаетсяРазрыв ? ': разрыв «⋯» стоит первым узлом списка' : ': разрыва перед первой строкой нет'),
    этоРазрыв === ожидаетсяРазрыв
  );
  const строкаПослеРазрыва = этоРазрыв ? дети[индексШапки + 2] : первыйУзелСписка;
  проверить(
    имяСценария + ': первая настоящая строка списка — место ' + местоПервой,
    Boolean(строкаПослеРазрыва) && строкаПослеРазрыва.getAttribute('data-место') === String(местоПервой)
  );
}

/** Проверить, что кнопка «Повторить» — следующий дочерний узел таблицы
    сразу за абзацем беды (класс «рейтинг-пояснение»), а не где-то дальше. */
function проверитьПовторитьСразуПослеАбзаца(таблица, названиеМеры) {
  const дети = таблица.children;
  let индексАбзаца = -1;
  for (let i = 0; i < дети.length; i++) {
    if (дети[i].classList && дети[i].classList.contains('рейтинг-пояснение')) { индексАбзаца = i; break; }
  }
  проверить('мера «' + названиеМеры + '»: абзац беды (.рейтинг-пояснение) нашёлся в таблице', индексАбзаца !== -1);
  const следующийУзел = индексАбзаца !== -1 ? дети[индексАбзаца + 1] : null;
  проверить(
    'мера «' + названиеМеры + '»: кнопка «Повторить» — следующий узел таблицы сразу за абзацем беды',
    Boolean(следующийУзел) && следующийУзел.id === 'кнопка-рейтинг-повторить'
  );
}

