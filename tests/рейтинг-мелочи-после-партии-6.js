/** Заменить в тексте набор искомых кусков на порченные — только если
    каждый искомый кусок реально нашёлся (иначе приём порчи устарел
    вместе с устройством файла, и молчать об этом нельзя). */
function испортитьКопию(текст, замены, имяПорчи) {
  for (const пара of замены) {
    if (текст.indexOf(пара.искомое) === -1) {
      console.log('ОШИБКА: приём порчи ' + имяПорчи + ' устарел — искомая строка не нашлась в ' + файлРейтинга + ':');
      console.log('  ' + пара.искомое);
      process.exit(1);
    }
  }
  let результат = текст;
  for (const пара of замены) результат = результат.split(пара.искомое).join(пара.замена);
  return результат;
}

/** Записать испорченную копию во временную папку (правило штаба: портим
    копию на диске, не файл проекта) и тут же прочитать её обратно —
    так порча гарантированно идёт из файла, а не только из памяти. */
function записатьВоВременную(текст, имяФайла) {
  const путь = path.join(os.tmpdir(), имяФайла);
  fs.writeFileSync(путь, текст, 'utf8');
  return fs.readFileSync(путь, 'utf8');
}

