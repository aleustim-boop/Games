/* Сколько всего столов личин открыто через эту обёртку и сколько звонков
   учёта пришло изнутри создатьСтолЛичин — должно быть ноль. */
let открытоСтолов = 0;
const учётИзСтоловЛичин = [];
function открытьСтолЛичин(игра, настройки) {
  const было = звонкиУчёта.length;
  const итог = комнаты.создатьСтолЛичин(игра, настройки);
  if (итог.ок) открытоСтолов++;
  for (const звонок of звонкиУчёта.slice(было)) учётИзСтоловЛичин.push(звонок);
  return итог;
}

/** Кто за столом: люди, личины, обычные боты (по местам). */
function составСтола(комната) {
  const состав = { люди: [], личины: [], боты: [] };
  for (const место of Object.keys(комната.игроки)) {
    const игрок = комната.игроки[место];
    if (!игрок || игрок.ушёл) continue;
    if (игрок.этоБот && игрок.личина) состав.личины.push(место);
    else if (игрок.этоБот) состав.боты.push(место);
    else состав.люди.push(место);
  }
  return состав;
}

/**
 * Дождаться хода личины в начатой партии дурака. Ход за гостем — гость
 * ходит первой картой (заходить можно любой), дальше очередь у личины.
 * Пауза хода личины в этой проверке укорочена (см. сценарийПар), ждём
 * по-настоящему, до восьми секунд.
 */
async function дождатьсяХодаЛичины(комната, местоГостя) {
  if (партии.чейХод(комната.партия) === местоГостя) {
    const ответ = комнаты.сделатьХод(комната, местоГостя, { действие: 'ходить', карта: 0 });
    проверить(ответ && ответ.принято === true, 'гость сходил первой картой (' + JSON.stringify(ответ && ответ.причина) + ')');
  }
  const послеГостя = комната.номерСобытия;
  for (let i = 0; i < 160; i++) {
    await пауза(50);
    const кто = комната.событие ? комната.игроки[комната.событие.кто] : null;
    if (комната.номерСобытия > послеГостя && кто && кто.этоБот && кто.личина) return комната.событие;
  }
  return null;
}

async function проверитьВсё() {
  // 1) Открыть стол личин шашек.
  const людейДо = комнаты.сколькоКомнатСЛюдьми();
  const шашки = открытьСтолЛичин('шашки', { сколькоЛичин: 1 });
  проверить(шашки.ок === true && typeof шашки.код === 'string', 'стол личин шашек открыт (' + JSON.stringify(шашки) + ')');
  if (!шашки.ок) return;
  const номерЛичины = шашки.личины[0];
  const личина = личины.личинаПоНомеру(номерЛичины);
  проверить(Boolean(личина), 'за столом личина из списка личин');
  проверить(комнаты.сколькоСтоловЛичин() === 1, 'столов личин: 1 (' + комнаты.сколькоСтоловЛичин() + ')');
  проверить(комнаты.сколькоКомнатСЛюдьми() === людейДо, 'стол личин не прибавил комнат с людьми');

  // 2) Список по сети видит стол.
  const сеть = await списокПоСети('шашки');
  const столы = сеть.тело.столы || [];
  const стол = столы.find(function (с) { return (с.игроки || []).indexOf(личина && личина.имя) !== -1; });
  проверить(Boolean(стол), 'стол личин виден в списке (/открытые-столы), имя личины в «игроки»');
  проверить(стол && стол.ботов === 0, 'в списке личина не считается ботом (ботов = ' + (стол && стол.ботов) + ')');
  проверить(стол && стол.занято === 1 && стол.свободно === 1, 'занято 1, свободно 1');
  проверить(сеть.текст.indexOf(String(номерЛичины)) === -1, 'номера личины в ответе списка нет');
  проверить(сеть.текст.indexOf('"' + шашки.код + '"') === -1, 'кода стола в ответе списка нет');

  // 3) Портреты в строке списка.
  const строка = строкаПоКоду('шашки', шашки.код);
  проверить(Boolean(строка), 'строка стола есть в комнаты.открытыеСтолы');
  const портреты = строка && строка.портреты;
  проверить(Array.isArray(портреты) && портреты.length === строка.игроки.length && портреты.length === 1,
    'портретов столько же, сколько имён (' + JSON.stringify(портреты) + ')');
  проверить(Array.isArray(портреты) && портреты.length > 0 && портреты.every(function (к) { return typeof к === 'string' && /^[0-9a-f]{24}$/.test(к); }),
    'портрет личины — непрозрачный ключ из 24 знаков');
  проверить(JSON.stringify(портреты || []).indexOf(String(личины.БАЗА_НОМЕРА || '9000000000')) === -1 &&
    JSON.stringify(портреты || []).indexOf(String(номерЛичины)) === -1, 'в портретах нет номеров личин');

  // 4) Защита «стол-призрак». Подопытный — открытый стол человека
  //    дурака на троих: человек + обычный бот (сел от подбора).
  const людской = комнаты.создатьКомнату('10.9.9.1', { игра: 'дурак', мест: 3, открытый: true, имя: 'Петя', телеграм: 7001 });
  проверить(людской.ок === true, 'открытый стол человека создан');
  /* Шпион учёта жив: у стола человека «комнатСоздано» обязан прийти.
     Иначе «стол личин в учёт не идёт» ниже ничего бы не значило. */
  проверить(звонкиУчёта.some(function (з) { return з.что === 'комнатСоздано' && з.игра === 'дурак'; }),
    'шпион учёта видит «комнатСоздано» у стола человека');
  const найден = людской.ок ? комнаты.найтиИгрока(людской.код, людской.пропуск) : null;
  проверить(Boolean(найден), 'комната стола человека найдена по пропуску');
  if (найден) {
    const комната = найден.комната;
    const посадка = комнаты.посадитьБотаОтПодбора(комната, 'обычный');
    проверить(посадка.принято === true && комната.этап === 'ожидание', 'обычный бот сел, место ещё есть');
    проверить(Boolean(строкаПоКоду('дурак', людской.код)), 'стол человека с ботом виден, пока человек за столом');
    const строкаЛюдей = строкаПоКоду('дурак', людской.код);
    проверить(строкаЛюдей && строкаЛюдей.ботов === 1 && строкаЛюдей.портреты.length === строкаЛюдей.игроки.length,
      'обычный бот в списке — бот, портретов столько же, сколько имён');
    const местоБота = Object.keys(комната.игроки).find(function (м) { return комната.игроки[м].этоБот; });
    /* Человека за столом больше нет: за столом один обычный бот, и хозяин
       теперь он. Не через «выйти» — та убирает комнату без людей целиком,
       и все «не виден» ниже прошли бы впустую, на пропавшей комнате. */
    delete комната.игроки[найден.ктоЯ];
    комната.хозяин = местоБота;
    проверить(комнаты.состояниеСтола(людской.код).есть === true, 'подопытная комната жива (иначе «не виден» ничего не значит)');
    проверить(!строкаПоКоду('дурак', людской.код), 'стол обычного бота без людей не виден (стол-призрак)');
    // 4а) Даже с признаком «стол личин» обычный бот-хозяин стол не открывает.
    комната.столЛичин = true;
    проверить(!строкаПоКоду('дурак', людской.код), 'стол личин с обычным ботом-хозяином не виден');
    // Тот же бот с личиной — виден: значит, решает именно личина.
    комната.игроки[местоБота].личина = { номер: личины.все()[39].номер };
    проверить(Boolean(строкаПоКоду('дурак', людской.код)), 'тот же стол с личиной-хозяином виден');
    // 4б) Личина-хозяин, но признака «стол личин» нет — не виден.
    комната.столЛичин = false;
    проверить(!строкаПоКоду('дурак', людской.код), 'личина-хозяин у стола без признака «стол личин» не виден');
    const закрытьЧужой = комнаты.закрытьСтолЛичин(людской.код);
    проверить(закрытьЧужой.ок === false && комнаты.состояниеСтола(людской.код).есть === true,
      'закрытьСтолЛичин стол людей не закрывает');
    проверить(комнаты.продлитьСтолЛичин(людской.код).ок === false, 'продлитьСтолЛичин стол людей не продлевает');
    комнаты.удалитьКомнату(людской.код);
  }

  // 5) Закрытие: при человеке — отказ; гость ушёл — стол снова ждёт.
  const большой = открытьСтолЛичин('дурак', { мест: 4, парами: true, сколькоЛичин: 2 });
  проверить(большой.ок === true, 'стол личин дурака 2×2 открыт (' + JSON.stringify(большой) + ')');
  const вход = большой.ок ? комнаты.войтиВКомнату(большой.код, { имя: 'Гость', телеграм: 7002 }) : { ок: false };
  проверить(вход.ок === true, 'человек сел за стол личин');
  проверить(комнаты.сколькоКомнатСЛюдьми() === людейДо + 1, 'стол личин с человеком — комната с людьми');
  const строкаСГостем = строкаПоКоду('дурак', большой.код);
  проверить(строкаСГостем && строкаСГостем.игроки.length === 3 && строкаСГостем.ботов === 0 &&
    строкаСГостем.игроки.indexOf('Гость') !== -1, 'в списке: гость и две личины, ботов 0');
  const отказ = комнаты.закрытьСтолЛичин(большой.код);
  проверить(отказ.ок === false, 'закрытьСтолЛичин при человеке за столом отказывает');
  проверить(комнаты.состояниеСтола(большой.код).есть === true, 'стол с человеком после отказа жив');
  const гость = вход.ок ? комнаты.найтиИгрока(вход.код, вход.пропуск) : null;
  проверить(Boolean(гость), 'гость найден по пропуску');
  if (гость) {
    проверить(typeof гость.комната.автоначалоВ === 'number', 'гость сел — ожидание автоначала заведено');
    комнаты.выйти(гость.комната, гость.ктоЯ);
    проверить(комнаты.состояниеСтола(большой.код).есть === true, 'гость ушёл из прихожей — стол личин остался');
    проверить(Boolean(строкаПоКоду('дурак', большой.код)), 'стол без гостя снова «ждёт» в списке');
    проверить(гость.комната.автоначалоВ === null, 'людей нет — автоначало снято');
    проверить(комнаты.сколькоКомнатСЛюдьми() === людейДо, 'пустой стол личин выпал из комнат с людьми');
  }
  проверить(комнаты.закрытьСтолЛичин(большой.код).ок === true, 'опустевший стол личин закрывается');
  проверить(комнаты.закрытьСтолЛичин(большой.код).ок === false, 'закрыть уже убранный стол — отказ, а не сбой');
  const закрытьШашки = комнаты.закрытьСтолЛичин(шашки.код);
  проверить(закрытьШашки.ок === true && комнаты.сколькоСтоловЛичин() === 0, 'стол без людей закрывается, столов личин 0');

  // 6) Отказы и «одна личина — один стол».
  проверить(открытьСтолЛичин('шашки', { сколькоЛичин: 2 }).ок === false, 'без свободного места стол не открывается');
  проверить(открытьСтолЛичин('нет-такой-игры', {}).ок === false, 'чужая игра — отказ');
  const первый = открытьСтолЛичин('нарды', { личины: [личины.все()[0].номер] });
  проверить(первый.ок === true && первый.личины[0] === личины.все()[0].номер, 'стол с названной личиной открыт');
  const второй = открытьСтолЛичин('нарды', { личины: [личины.все()[0]] });
  проверить(второй.ок === false, 'занятую личину за второй стол не сажает');
  const разные = [];
  const кодыШахмат = [];
  for (let i = 0; i < 5; i++) {
    const с = открытьСтолЛичин('шахматы', {});
    if (с.ок) { разные.push(с.личины[0]); кодыШахмат.push(с.код); }
  }
  проверить(разные.length === 5 && new Set(разные.concat(первый.личины)).size === 6, 'пять столов — пять разных личин');
  проверить(комнаты.занятыеЛичины().size === 6, 'занятых личин ровно 6');
  проверить(комнаты.сколькоКомнатСЛюдьми() === людейДо, 'столы без людей в «комнаты с людьми» не входят');

  // 7) Э3: человек сел — партия идёт.
  await сценарийПар();
  await сценарийМонополии();
  сценарийХозяинЧеловек();
  сценарийПолногоСтола();

  // 8) Групповой стол без хозяина — в счёте людей, хоть никто ещё не сел.
  const людейПередЧатом = комнаты.сколькоКомнатСЛюдьми();
  const изЧата = комнаты.создатьКомнату('10.7.7.7', { игра: 'дурак', безХозяина: true });
  проверить(изЧата.ок === true && изЧата.безХозяина === true, 'групповой стол без хозяина открыт');
  проверить(комнаты.сколькоКомнатСЛюдьми() === людейПередЧатом + 1,
    'стол без хозяина входит в сколькоКомнатСЛюдьми (' + комнаты.сколькоКомнатСЛюдьми() + ' из ' + (людейПередЧатом + 1) + ')');
  if (изЧата.ок) комнаты.удалитьКомнату(изЧата.код);

  // 9) Запас под потолком и место человеку на самом потолке.
  const нужно = комнаты.ПОТОЛОК_КОМНАТ - комнаты.ЗАПАС_КОМНАТ_ДЛЯ_ЛЮДЕЙ - комнаты.сколькоКомнат();
  проверить(комнаты.ЗАПАС_КОМНАТ_ДЛЯ_ЛЮДЕЙ >= комнаты.ПОТОЛОК_КОМНАТ * 0.1, 'запас не меньше 10 % потолка');
  const пустышки = [];
  for (let i = 0; i < нужно; i++) {
    const к = комнаты.создатьКомнату('10.8.' + Math.floor(i / 200) + '.' + (i % 200), { игра: 'шашки' });
    if (к.ок) пустышки.push(к.код);
  }
  проверить(пустышки.length === нужно && нужно > 0, 'набрали комнат до порога (' + пустышки.length + ' из ' + нужно + ')');
  проверить(открытьСтолЛичин('шашки', {}).ок === false, 'у порога потолка стол личин не открывается');
  комнаты.удалитьКомнату(пустышки.pop());
  const уПорога = открытьСтолЛичин('шашки', {});
  проверить(уПорога.ок === true, 'на одну комнату ниже порога — открывается');
  await сценарийПотолка(пустышки, первый, кодыШахмат);
  for (const код of пустышки) комнаты.удалитьКомнату(код);

  // 10) Уборка и продление.
  const столовДо = комнаты.сколькоСтоловЛичин();
  проверить(столовДо >= 2, 'для уборки есть хотя бы два стола личин (' + столовДо + ')');
  комнаты.прибратьсяСейчас();
  проверить(комнаты.сколькоСтоловЛичин() === столовДо, 'свежие столы личин уборка не трогает');
  сдвиг += комнаты.ЖИЗНЬ_ПУСТОЙ_КОМНАТЫ - 60 * 1000;
  проверить(комнаты.продлитьСтолЛичин(уПорога.код).ок === true, 'продлитьСтолЛичин принят');
  сдвиг += 65 * 1000;
  комнаты.прибратьсяСейчас();
  проверить(комнаты.состояниеСтола(уПорога.код).есть === true, 'продлённый стол пережил срок пустой комнаты');
  проверить(комнаты.сколькоСтоловЛичин() === 1, 'непродлённые столы личин убраны (' + комнаты.сколькоСтоловЛичин() + ')');
  сдвиг += комнаты.ЖИЗНЬ_ПУСТОЙ_КОМНАТЫ + 5000;
  комнаты.прибратьсяСейчас();
  проверить(комнаты.сколькоСтоловЛичин() === 0, 'через срок пустой комнаты уборка убрала и его (' + комнаты.сколькоСтоловЛичин() + ')');

  // Итог учёта: ни один стол личин не позвал учёт людей.
  проверить(открытоСтолов >= 12, 'столов личин открыто достаточно для вывода (' + открытоСтолов + ')');
  проверить(учётИзСтоловЛичин.length === 0,
    'создатьСтолЛичин не зовёт «комнатСоздано» и учестьЧеловека (' + JSON.stringify(учётИзСтоловЛичин) + ')');
}

/** Дурак 2×2, две личины: гость сел по сети — через 20–40 с партия сама. */
async function сценарийПар() {
  const ЖДАТЬ = комнаты.ЖДАТЬ_ДРУГИХ_МС;
  проверить(ЖДАТЬ && ЖДАТЬ.от === 20000 && ЖДАТЬ.до === 40000, 'ожидание второго человека — 20–40 с (решение В4)');
  const пары = открытьСтолЛичин('дурак', { мест: 4, парами: true, сколькоЛичин: 2 });
  проверить(пары.ок === true, 'Э3: стол личин дурака 2×2 открыт');
  if (!пары.ок) return;
  /* Личина думает как человек — до 22 с. Здесь нужен сам факт хода,
     поэтому паузу укорачиваем (подмена в памяти, на время сценария). */
  const настоящаяПауза = личины.паузаХода;
  личины.паузаХода = function () { return 30; };
  try {
    const до = Date.now();
    const вход = await спросить('/войти', { код: пары.код, имя: 'Гость', initData: подпись(7101, 'Гость') });
    проверить(вход.код === 200 && typeof вход.тело.пропуск === 'string', 'гость сел за стол личин по сети (/войти, ' + вход.код + ')');
    const я = вход.тело.пропуск ? комнаты.найтиИгрока(пары.код, вход.тело.пропуск) : null;
    проверить(Boolean(я), 'гость найден по пропуску');
    if (!я) return;
    const комната = я.комната;
    проверить(комната.этап === 'ожидание', 'сразу после входа партия не началась — ждём второго человека');
    const срок = комната.автоначалоВ;
    проверить(typeof срок === 'number' && срок >= до + ЖДАТЬ.от && срок <= Date.now() + ЖДАТЬ.до,
      'ожидание заведено на 20–40 с (через ' + Math.round((срок - до) / 1000) + ' с)');
    const опрос = function () { комнаты.найтиИгрока(пары.код, вход.тело.пропуск); };
    комнаты.прибратьсяСейчас();
    проверить(комната.этап === 'ожидание', 'уборка до срока партию не начинает');
    /* Часы двигаем шагами по 10 с с опросом гостя, как живая вкладка:
       молчание дольше 12 с — уже «нет связи», и стол честно не начнёт. */
    while (Date.now() < срок - 1000 - 10000) { сдвиг += 10000; опрос(); комнаты.прибратьсяСейчас(); }
    сдвиг += срок - Date.now() - 1000;
    опрос();
    комнаты.прибратьсяСейчас();
    проверить(комната.этап === 'ожидание', 'за секунду до срока — ещё ждём');
    сдвиг += 2000;
    опрос();
    комнаты.прибратьсяСейчас();
    проверить(комната.этап === 'игра', 'срок вышел — партия началась сама (этап ' + комната.этап + ')');
    const перваяПартия = комната.партия;
    const номерПартии = комната.номерПартии;
    опрос();
    комнаты.прибратьсяСейчас();
    проверить(комната.партия === перваяПартия && комната.номерПартии === номерПартии && комната.этап === 'игра',
      'повторная уборка после старта второй раз не начинает');
    const состав = составСтола(комната);
    проверить(состав.люди.length === 1 && состав.люди[0] === я.ктоЯ, 'за столом один человек — гость');
    проверить(состав.личины.length === 3, 'за столом три личины (' + состав.личины.length + ')');
    проверить(состав.боты.length === 0, 'обычных ботов нет');
    const номера = состав.личины.map(function (м) { return комната.игроки[м].личина.номер; });
    проверить(new Set(номера).size === 3, 'три разные личины');
    проверить(комната.автоначалоВ === null, 'партия идёт — ожидание снято');
    проверить(комната.партия && комната.партия.игроки && комната.партия.игроки.length === 4, 'в партии четверо');
    const ход = await дождатьсяХодаЛичины(комната, я.ктоЯ);
    проверить(Boolean(ход), 'ход личины пришёл (' + JSON.stringify(ход) + ')');
  } finally {
    личины.паузаХода = настоящаяПауза;
    комнаты.удалитьКомнату(пары.код);
  }
}

/** Монополия на 4 с одной личиной: человек сел — после срока старт. */
async function сценарийМонополии() {
  const мон = открытьСтолЛичин('монополия', { мест: 4, сколькоЛичин: 1 });
  проверить(мон.ок === true, 'Э3: стол личин монополии на 4 открыт (' + JSON.stringify(мон) + ')');
  if (!мон.ок) return;
  const вход = await спросить('/войти', { код: мон.код, имя: 'Игрок', initData: подпись(7102, 'Игрок') });
  проверить(вход.код === 200 && typeof вход.тело.пропуск === 'string', 'человек сел за монополию по сети');
  const я = вход.тело.пропуск ? комнаты.найтиИгрока(мон.код, вход.тело.пропуск) : null;
  if (!я) { проверить(false, 'человек найден по пропуску'); return; }
  const комната = я.комната;
  проверить(комната.этап === 'ожидание' && typeof комната.автоначалоВ === 'number', 'монополия ждёт второго человека');
  // Вкладка закрыта: опросов нет, срок вышел — без человека не начинаем.
  сдвиг += комнаты.ЖДАТЬ_ДРУГИХ_МС.до + 1000;
  комнаты.прибратьсяСейчас();
  проверить(комната.игроки[я.ктоЯ] && комната.игроки[я.ктоЯ].наСвязи === false, 'гость молчит — он не на связи');
  проверить(комната.этап === 'ожидание', 'вкладка закрыта — партия без человека не началась (этап ' + комната.этап + ')');
  проверить(typeof комната.автоначалоВ === 'number' && комната.автоначалоВ > Date.now() + комнаты.ЖДАТЬ_ДРУГИХ_МС.от - 1000,
    'срок не снят, а отложен на новый круг 20–40 с');
  // Гость вернулся: опрос — и после нового срока стол начинает.
  const опрос = function () { комнаты.найтиИгрока(мон.код, вход.тело.пропуск); };
  while (Date.now() < комната.автоначалоВ) { сдвиг += 10000; опрос(); комнаты.прибратьсяСейчас(); }
  опрос();
  комнаты.прибратьсяСейчас();
  проверить(комната.этап === 'игра', 'монополия: гость на связи — партия началась (этап ' + комната.этап + ')');
  const состав = составСтола(комната);
  проверить(состав.люди.length === 1 && состав.личины.length === 3 && состав.боты.length === 0,
    'монополия: 1 человек + 3 личины (' + JSON.stringify(состав) + ')');
  сценарийУшёлПоследнийЧеловек(комната, я.ктоЯ);
  комнаты.удалитьКомнату(мон.код);
}

/** Хозяин-личина ушла, хозяином стал человек — автоначало снято. */
function сценарийХозяинЧеловек() {
  const стол = открытьСтолЛичин('дурак', { мест: 3, сколькоЛичин: 1 });
  проверить(стол.ок === true, 'Э3: стол личин дурака на троих открыт');
  if (!стол.ок) return;
  const вход = комнаты.войтиВКомнату(стол.код, { имя: 'Хозяйка', телеграм: 7103 });
  const я = вход.ок ? комнаты.найтиИгрока(вход.код, вход.пропуск) : null;
  if (!я) { проверить(false, 'гость за столом на троих найден'); return; }
  const комната = я.комната;
  проверить(typeof комната.автоначалоВ === 'number', 'на троих: ожидание заведено');
  комнаты.выйти(комната, комната.хозяин);   // личина-хозяин ушла из прихожей
  проверить(комната.хозяин === я.ктоЯ, 'хозяином стал человек');
  проверить(комната.автоначалоВ === null, 'хозяин-человек — автоначало снято');
  сдвиг += комнаты.ЖДАТЬ_ДРУГИХ_МС.до + 1000;
  комнаты.найтиИгрока(вход.код, вход.пропуск);   // человек на связи, как живой опрос
  комнаты.прибратьсяСейчас();
  проверить(комната.этап === 'ожидание' && комната.автоначалоВ === null,
    'хозяин-человек: уборка партию сама не начинает');
  комнаты.удалитьКомнату(стол.код);
}

/** Стол собрали люди целиком — ждать некого, старт через паузу полного стола. */
function сценарийПолногоСтола() {
  const стол = открытьСтолЛичин('дурак', { мест: 3, сколькоЛичин: 1 });
  проверить(стол.ок === true, 'Э3: второй стол на троих открыт');
  if (!стол.ок) return;
  комнаты.войтиВКомнату(стол.код, { имя: 'Первый', телеграм: 7104 });
  const второй = комнаты.войтиВКомнату(стол.код, { имя: 'Второй', телеграм: 7105 });
  const я = второй.ок ? комнаты.найтиИгрока(второй.код, второй.пропуск) : null;
  if (!я) { проверить(false, 'второй гость найден'); return; }
  const комната = я.комната;
  проверить(комната.этап === 'ожидание' && комната.автоначалоВ <= Date.now() + комнаты.ПАУЗА_ПОЛНОГО_СТОЛА_МС,
    'стол полон — старт не позже паузы полного стола');
  сдвиг += комнаты.ПАУЗА_ПОЛНОГО_СТОЛА_МС + 500;
  комнаты.прибратьсяСейчас();
  const состав = составСтола(комната);
  проверить(комната.этап === 'игра' && состав.люди.length === 2 && состав.личины.length === 1,
    'полный стол: партия пошла, 2 человека + 1 личина');
  сценарийЛичинаУшла(комната, состав);
  комнаты.удалитьКомнату(стол.код);
}

/**
 * Партию закончить руками: правила здесь не проверяем, нужен этап «конец».
 * Итог отмечен учтённым, как после настоящего конца, — иначе «партийБрошено»
 * при уборке комнаты был бы от нашей подделки, а не от проверяемого кода.
 */
function закончитьПартию(комната) {
  комната.партия.завершена = true;
  комната.партияУчтена = true;
  комната.этап = 'конец';
}

/**
 * Конец партии, личина ушла (как в личинаПослеПартии: ушёл, «не хочет
 * ещё»), оба человека жмут «Ещё партию» — реванш обязан собраться,
 * а не висеть на «ждём остальных».
 */
function сценарийЛичинаУшла(комната, состав) {
  if (комната.этап !== 'игра' || состав.личины.length !== 1) { проверить(false, 'после партии: нужен идущий стол 2 + 1'); return; }
  const номер = комната.номерПартии;
  закончитьПартию(комната);
  комнаты.выйти(комната, состав.личины[0]);
  проверить(комната.игроки[состав.личины[0]] && комната.игроки[состав.личины[0]].ушёл === true,
    'после партии: личина ушла, место за ней ещё числится');
  const первый = комнаты.сделатьХод(комната, состав.люди[0], { действие: 'ещё' });
  проверить(первый && первый.принято === true, 'после партии: первый человек позвал ещё (' + JSON.stringify(первый && первый.причина) + ')');
  комнаты.сделатьХод(комната, состав.люди[1], { действие: 'ещё' });
  проверить(комната.этап === 'игра' && комната.номерПартии === номер + 1,
    'личина ушла — «Ещё партию» двух людей собрало реванш (этап ' + комната.этап + ')');
  проверить(!комната.игроки[состав.личины[0]], 'ушедшая личина в новую партию не попала');
}

/**
 * Конец партии монополии, личины согласны, ушёл единственный человек —
 * реванш одних личин не раздаётся и в статистику партий не идёт.
 */
function сценарийУшёлПоследнийЧеловек(комната, ктоЯ) {
  if (комната.этап !== 'игра') { проверить(false, 'без людей: нужна идущая партия'); return; }
  const номер = комната.номерПартии;
  закончитьПартию(комната);
  for (const место of Object.keys(комната.игроки)) {
    if (место !== ктоЯ) комната.игроки[место].хочетЕщё = true;   // личины сказали «ещё»
  }
  const было = звонкиУчёта.length;
  комнаты.выйти(комната, ктоЯ);
  const партийныеЗвонки = звонкиУчёта.slice(было).filter(function (з) { return /^партий/.test(з.что); });
  проверить(комната.этап !== 'игра' && комната.номерПартии === номер,
    'ушёл последний человек — реванш личинам не раздан (этап ' + комната.этап + ')');
  проверить(партийныеЗвонки.length === 0, 'в статистику партий ничего не ушло (' + JSON.stringify(партийныеЗвонки) + ')');
}

/**
 * На самом потолке комнат человек получает место: уходит самый давний
 * пустой стол личин. Самый давний здесь — стол нард (первый): за него
 * садится гость, и тогда уйти обязан другой — первый стол шахмат.
 */
async function сценарийПотолка(пустышки, нарды, кодыШахмат) {
  const гостьНард = комнаты.войтиВКомнату(нарды.код, { имя: 'Нардист', телеграм: 7106 });
  проверить(гостьНард.ок === true, 'гость сел за самый давний стол личин (нарды)');
  let добрали = 0;
  while (комнаты.сколькоКомнат() < комнаты.ПОТОЛОК_КОМНАТ) {
    const к = комнаты.создатьКомнату('10.6.' + Math.floor(добрали / 200) + '.' + (добрали % 200), { игра: 'шашки' });
    if (!к.ок) break;
    пустышки.push(к.код);
    добрали++;
  }
  проверить(комнаты.сколькоКомнат() === комнаты.ПОТОЛОК_КОМНАТ, 'сервер полон: ' + комнаты.сколькоКомнат() + ' комнат');
  const столовДо = комнаты.сколькоСтоловЛичин();
  const человек = комнаты.создатьКомнату('10.5.5.5', { игра: 'шашки', имя: 'Опоздавший', телеграм: 7107 });
  проверить(человек.ок === true, 'на потолке человек получил место (' + JSON.stringify(человек.причина || '') + ')');
  if (человек.ок) пустышки.push(человек.код);
  проверить(комнаты.сколькоСтоловЛичин() === столовДо - 1, 'ушёл ровно один стол личин (' + столовДо + ' → ' + комнаты.сколькоСтоловЛичин() + ')');
  проверить(комнаты.состояниеСтола(нарды.код).есть === true, 'стол личин с гостем не тронут');
  проверить(кодыШахмат.length > 0 && комнаты.состояниеСтола(кодыШахмат[0]).есть === false,
    'ушёл самый давний пустой стол личин');
  комнаты.удалитьКомнату(нарды.код);
}

