/* =====================================================================
   СНИМОК ШТОРКИ ВЫБОРА ИГРЫ (план «Шторка выбора игры», раздел tests/).

   Зачем этот файл. На экране рейтинга кнопка «Дурак ▾» открывает шторку
   выбора игры снизу — заголовок «Выбрать игру», раздел «ИГРЫ», пункты
   с большим значком (для пальца) и галочкой у активной игры. Файл
   открывает экран рейтинга, жмёт кнопку выбора игры, ждёт панель и
   снимает её на 390×844 — а заодно измеряет числами то, что руками не
   разглядеть (высоту пункта, размер значка, положение галочки в кадре).
   Картинку смотрит смотритель глазами, числа — эта проверка.

   Приём — тот же, что в tests/снимок-рейтинг-эталон.js: свой статический
   сервер на свободном порту (раздаёт папку проекта как есть), поддельный
   Telegram и перехват двери /рейтинг — из tests/браузер-робот.js.

   Обычный запуск — открывает шторку и печатает «Итого проверок: N,
   провалов: M»:
       node tests/снимок-рейтинга-с-панелью.js

   Ломающий запуск — портит КОПИЮ style.css в памяти (настоящий файл
   проекта не трогает ни на секунду) и требует провала (правило штаба
   «каждая проверка обязана уметь краснеть»):
       node tests/снимок-рейтинга-с-панелью.js --сломать
   Три поломки:
     а) .рейтинг-панель-игр__пункт: min-height 70px → 40px — красит
        проверку «высота пункта ≥ 70px»;
     б) .рейтинг-панель-игр__значок: 50×50 → 30×30 — красит проверку
        «значок 50×50»;
     в) .рейтинг-панель-игр__раздел получает display: none — раздел
        «ИГРЫ» перестаёт быть виден — красит проверку «раздел «ИГРЫ» виден».
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const http = require('http');
const { chromium, подготовитьПодделку, перехватить } = require('./браузер-робот.js');

const КОРЕНЬ = path.join(__dirname, '..');
const ПАПКА_СНИМКОВ = path.join(__dirname, 'снимки');
const АДРЕС_ХОЗЯИНА = '127.0.0.1';
const ЗАПРЕЩЁННЫЕ_ПОРТЫ = [8790, 8791, 8080];
const ПУТЬ_СТИЛЯ = path.join(КОРЕНЬ, 'style.css');
const сломать = process.argv.indexOf('--сломать') !== -1;

function свободныйПорт() {
  return new Promise((готово, брак) => {
    const проба = http.createServer();
    проба.on('error', брак);
    проба.listen(0, АДРЕС_ХОЗЯИНА, () => {
      const порт = проба.address().port;
      проба.close(() => готово(порт));
    });
  });
}

async function выбратьСвободныйПорт() {
  for (let попытка = 0; попытка < 6; попытка++) {
    const порт = await свободныйПорт();
    if (ЗАПРЕЩЁННЫЕ_ПОРТЫ.indexOf(порт) === -1) return порт;
  }
  throw new Error('не удалось получить свободный порт, отличный от боевых 8790/8791 и от 8080');
}

const ТИПЫ_ФАЙЛОВ = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.woff2': 'font/woff2'
};

function запрещённыйАдрес(адрес) {
  const низ = адрес.toLowerCase();
  if (низ.indexOf('.env') !== -1) return true;
  const части = низ.split(/[\\/]/).filter(Boolean);
  if (части.length && части[0] === 'bot') return true;
  return части.some((часть) => часть.charAt(0) === '.');
}

function создатьИспорченныйСтиль(поломки) {
  const оригинал = fs.readFileSync(ПУТЬ_СТИЛЯ, 'utf8');
  let испорченный = оригинал;

  if (поломки.indexOf('а') !== -1) {
    // Поломка а) — пункт панели ниже требуемых 70px под палец
    const искомое = '.рейтинг-панель-игр__пункт {';
    if (испорченный.indexOf(искомое) === -1) {
      throw new Error('Поломка а): не найден селектор «' + искомое + '» в style.css');
    }
    испорченный = испорченный.split(искомое).join(искомое + '\n  min-height: 40px !important;');
  }

  if (поломки.indexOf('б') !== -1) {
    // Поломка б) — значок игры мельче требуемых 50×50
    const искомое = '.рейтинг-панель-игр__значок {';
    if (испорченный.indexOf(искомое) === -1) {
      throw new Error('Поломка б): не найден селектор «' + искомое + '» в style.css');
    }
    испорченный = испорченный.split(искомое).join(искомое + '\n  width: 30px !important;\n  height: 30px !important;');
  }

  if (поломки.indexOf('в') !== -1) {
    // Поломка в) — раздел «ИГРЫ» прячется совсем
    const искомое = '.рейтинг-панель-игр__раздел {';
    if (испорченный.indexOf(искомое) === -1) {
      throw new Error('Поломка в): не найден селектор «' + искомое + '» в style.css');
    }
    испорченный = испорченный.split(искомое).join(искомое + '\n  display: none !important;');
  }

  return испорченный;
}

function поднятьСервер(порт, подменаStyleCss) {
  return new Promise((готово) => {
    const сервер = http.createServer((запрос, ответ) => {
      let адрес;
      try {
        адрес = decodeURIComponent(запрос.url.split('?')[0]);
      } catch (ошибка) {
        ответ.writeHead(400); ответ.end('непонятный адрес'); return;
      }
      if (адрес === '/') адрес = '/index.html';
      if (запрещённыйАдрес(адрес)) { ответ.writeHead(403); ответ.end('доступ закрыт'); return; }

      if (подменаStyleCss !== null && адрес === '/style.css') {
        ответ.writeHead(200, { 'Content-Type': 'text/css; charset=utf-8', 'Cache-Control': 'no-store' });
        ответ.end(подменаStyleCss);
        return;
      }

      const относительный = адрес.replace(/^\/+/, '');
      const файл = path.join(КОРЕНЬ, относительный);
      if (файл !== КОРЕНЬ && !файл.startsWith(КОРЕНЬ + path.sep)) {
        ответ.writeHead(403); ответ.end('доступ закрыт: файл вне папки проекта'); return;
      }

      fs.readFile(файл, (ошибка, данные) => {
        if (ошибка) { ответ.writeHead(404); ответ.end('не найдено: ' + адрес); return; }
        ответ.writeHead(200, {
          'Content-Type': ТИПЫ_ФАЙЛОВ[path.extname(файл).toLowerCase()] || 'application/octet-stream',
          'Cache-Control': 'no-store'
        });
        ответ.end(данные);
      });
    });
    сервер.listen(порт, АДРЕС_ХОЗЯИНА, () => готово(сервер));
  });
}

function лидер(место, имя, очки, этоЯ) {
  return {
    место: место, имя: имя, очки: очки,
    побед: Math.max(1, Math.round(очки / 5)), партий: Math.max(1, Math.round(очки / 4)),
    этоЯ: Boolean(этоЯ), движение: 'безИзменений', сдвиг: 0
  };
}

