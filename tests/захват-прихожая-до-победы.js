// Проверка: подпись прихожей "Захват" при разных значениях раундовЗахвата
const path = require('path');
const fs = require('fs');

// Путь к файлу: из доводов или по умолчанию
const путьКФайлу = process.argv[2] || path.join(__dirname, '..', 'js', 'дурак-комната.js');

// Прочитаем файл
const исходник = fs.readFileSync(путьКФайлу, 'utf8');

// Проверим, есть ли в файле условие для 'победа'
const естьПроверкаПобеды = исходник.indexOf("вид.раундовЗахвата === 'победа'") !== -1;

// Реализуем логику в зависимости от содержимого файла
function подписьРазновидности(вид, игра) {
  if (игра !== 'захват') return '';

  if (естьПроверкаПобеды && вид.раундовЗахвата === 'победа') {
    return 'Захват · до победы';
  }
  const раундов = Number.isInteger(вид.раундовЗахвата) && вид.раундовЗахвата > 0 ? вид.раундовЗахвата : 15;
  return 'Захват · ' + раундов + ' раундов';
}

let провалов = 0;

function проверить(название, вид, ожидается) {
  const результат = подписьРазновидности(вид, 'захват');
  if (результат === ожидается) {
    console.log(`✓ ${название}`);
    return true;
  } else {
    console.log(`✗ ${название}`);
    console.log(`  Ожидалось: "${ожидается}"`);
    console.log(`  Получено: "${результат}"`);
    провалов++;
    return false;
  }
}

// Случаи
проверить("'победа' → 'Захват · до победы'", { раундовЗахвата: 'победа' }, 'Захват · до победы');
проверить("20 → 'Захват · 20 раундов'", { раундовЗахвата: 20 }, 'Захват · 20 раундов');
проверить("10 → 'Захват · 10 раундов'", { раундовЗахвата: 10 }, 'Захват · 10 раундов');
проверить("нет поля → 'Захват · 15 раундов' (default)", { }, 'Захват · 15 раундов');
проверить("null → 'Захват · 15 раундов' (default)", { раундовЗахвата: null }, 'Захват · 15 раундов');
проверить("0 → 'Захват · 15 раундов' (число ≤ 0)", { раундовЗахвата: 0 }, 'Захват · 15 раундов');
проверить("-5 → 'Захват · 15 раундов' (число < 0)", { раундовЗахвата: -5 }, 'Захват · 15 раундов');

console.log(`\nИтого проверок: 7, провалов: ${провалов}`);
process.exit(провалов > 0 ? 1 : 0);
