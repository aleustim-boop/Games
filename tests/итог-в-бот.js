/** Копия модуля (с соседями, которые он require'ит) во временной папке, с одной порчей. */
function испорченнаяКопия(порча) {
  const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'итог-в-бот-копия-'));
  for (const имя of ['итог-в-бот.js', 'названия.js', 'личины.js']) {
    fs.copyFileSync(path.join(КОРЕНЬ, 'server', имя), path.join(врем, имя));
  }
  const файл = path.join(врем, 'итог-в-бот.js');
  // Зависимость словаря остаётся настоящей; портим только проверяемый модуль.
  fs.writeFileSync(файл, fs.readFileSync(файл, 'utf8').replace("require('../общее/js/языки')", 'require(' + JSON.stringify(path.join(КОРЕНЬ, 'общее', 'js', 'языки.js')) + ')'));
  const текст = fs.readFileSync(файл, 'utf8').replace(/\r\n/g, '\n');
  const сколько = текст.split(порча.было).length - 1;
  if (сколько !== 1) {
    process.stdout.write('ПОРЧА НЕ СОСТОЯЛАСЬ: нужная строка найдена ' + сколько + ' раз(а), а ждали ровно один. ' +
      'Модуль переписали — поправьте порчу в tests/итог-в-бот.js.\n');
    process.exit(2);
  }
  fs.writeFileSync(файл, текст.split(порча.было).join(порча.стало), 'utf8');
  return файл;
}

