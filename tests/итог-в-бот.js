const АДРЕС = 'https://igra.test';

function стенд(настройки) {
  настройки = настройки || {};
  const мир = {
    время: 1000000,
    задачи: [],
    отправки: [],            // { время, тело }
    запретили: [],           // [номер, причина]
    отказы: new Map(),       // номер → причина
    ответ: настройки.ответ || function () { return { ok: true }; },
    журнал: []
  };
  const имена = настройки.имена || {};
  /* неСтирать — подключить поддельный мир, не трогая очередь модуля:
     так видно, не накопил ли модуль писем, пока был выключен. */
  if (!настройки.неСтирать) итог.забытьВсё();
  итог.подключить(Object.assign({
    отправить: function (тело) {
      мир.отправки.push({ время: мир.время, тело: тело });
      return мир.ответ(тело, мир.отправки.filter(function (о) { return о.тело.chat_id === тело.chat_id; }).length);
    },
    почемуНеЗвать: function (номер) { return мир.отказы.get(номер) || ''; },
    запретить: function (номер, причина) { мир.запретили.push([номер, причина]); мир.отказы.set(номер, причина); },
    имяПоНомеру: function (номер) { return имена[номер] || ''; },
    адресИгры: АДРЕС,
    имяБота: 'test_bot',
    сейчас: function () { return мир.время; },
    отложить: function (дело, мс) { мир.задачи.push({ когда: мир.время + мс, дело: дело }); return 0; }
  }, настройки.зависимости || {}));
  return мир;
}

const ждатьТик = function () { return new Promise(function (ок) { setImmediate(ок); }); };

/** Прогнать виртуальное время до тишины: письма, паузы, повторы. */
async function прогнать(мир) {
  for (let круг = 0; круг < 100000; круг++) {
    for (let тик = 0; тик < 4; тик++) await ждатьТик();
    if (!мир.задачи.length) return;
    мир.задачи.sort(function (а, б) { return а.когда - б.когда; });
    const задача = мир.задачи.shift();
    if (задача.когда > мир.время) мир.время = задача.когда;
    задача.дело();
  }
  throw new Error('прогон не кончился');
}

function кому(мир, номер) {
  return мир.отправки.filter(function (о) { return о.тело.chat_id === номер; });
}

const ЧЕЛОВЕК = function (номер, исход, очков, напарник) {
  return { номер: номер, этоБот: false, имя: 'самоназвание', исход: исход, очков: очков, напарник: напарник === undefined ? null : напарник };
};
const БОТ = function (исход) { return { номер: null, этоБот: true, имя: 'Бот', исход: исход }; };
/** Игра парами: то же место, но с номером места за столом и номером МЕСТА напарника. */
const ЗА_СТОЛОМ = function (кто, место, местоНапарника) {
  return Object.assign({}, кто, { место: место, напарник: местоНапарника });
};
const ГОСТЬ = function (исход) { return { номер: null, этоБот: false, имя: 'Гость', исход: исход }; };

