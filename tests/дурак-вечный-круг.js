/*
 * Проверка правила «вечный круг» в дураке (решение владельца 29.09).
 *
 * Колода пуста, расклад на руках повторяется, отбой не растёт — партия
 * обязана кончиться на третьем повторе одного положения, дурак — тот,
 * у кого больше карт. Поровну вдвоём или у пар — ничья (партия.ничья).
 *
 * Запуск:
 *   node tests/дурак-вечный-круг.js            — обычная проверка, должна быть зелёной;
 *   node tests/дурак-вечный-круг.js --сломать  — грузит КОПИЮ js/game.js из временной
 *       папки, где вызов проверки круга вырезан, и обязана покраснеть.
 *       Файл проекта не трогается.
 */
'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ФАЙЛ_ИГРЫ = path.join(КОРЕНЬ, 'js', 'game.js');
const СЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;

let проверок = 0;
let провалов = 0;
function проверить(условие, что) {
  проверок++;
  if (условие) return;
  провалов++;
  console.log('ПРОВАЛ: ' + что);
}

/* Строка вызова проверки круга в «завершитьПодход». Её и вырезает ломающий
   запуск. Не нашлась ровно одна — это провал, а не пропуск: значит правило
   переименовали, и проверка больше не знает, что ломать. */
const ВЫЗОВ_КРУГА = /\n[ \t]*if \(подходБыл\) проверитьКруг\(партия\);/g;

function загрузитьИгру() {
  if (!СЛОМАТЬ) return require(ФАЙЛ_ИГРЫ);
  const текст = fs.readFileSync(ФАЙЛ_ИГРЫ, 'utf8');
  const найдено = текст.match(ВЫЗОВ_КРУГА) || [];
  if (найдено.length !== 1) {
    console.log('ПРОВАЛ: вызов проверки круга в game.js найден ' + найдено.length +
                ' раз вместо одного — ломать нечего');
    console.log('Итого проверок: 1, провалов: 1');
    process.exit(1);
  }
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'дурак-круг-'));
  const копия = path.join(папка, 'game.js');
  fs.writeFileSync(копия, текст.replace(ВЫЗОВ_КРУГА, ''));
  console.log('Ломающий запуск: копия без правила круга — ' + копия);
  return require(копия);
}

const игра = загрузитьИгру();

/* ---------------------------------------------------------------------
   Сборка расклада руками
   --------------------------------------------------------------------- */

/** Карта из записи «6♣», «10♥», «В♠» — вес берём из самой игры. */
function карта(запись) {
  const масть = запись.slice(-1);
  const имя = запись.slice(0, -1);
  return { масть: масть, имя: имя, вес: игра.ВСЕ_ДОСТОИНСТВА.indexOf(имя) + 2 };
}

/**
 * Партия с пустой колодой и заданными руками. Недостающие карты лежат
 * в отбое — так карт в партии столько же, сколько в колоде.
 */
function собратьРасклад(настройки, козырь, руки, местоАтаки) {
  const партия = игра.создатьПартию(настройки);
  const занятые = new Set();
  партия.игроки.forEach(function (имя, i) {
    партия.руки[имя] = руки[i].map(карта);
    for (const к of партия.руки[имя]) занятые.add(к.имя + к.масть);
  });
  const все = игра.собратьКолоду(партия.размерКолоды);
  партия.отбой = все.filter(function (к) { return !занятые.has(к.имя + к.масть); });
  партия.колода = [];
  партия.стол = [];
  партия.пасы = [];
  партия.берёт = false;
  партия.подходов = 10;
  партия.козырь = козырь;
  партия.козырнаяКарта = все.filter(function (к) { return к.масть === козырь; })[0];
  партия.местоАтаки = местоАтаки;
  return партия;
}

/**
 * Доиграть партию ботами «обычный». Возвращает число ходов; упёрлась
 * в потолок — значит партия не кончилась сама.
 */
const ПОТОЛОК_ХОДОВ = 2000;
function доигратьБотами(партия) {
  let ходов = 0;
  while (!партия.завершена && ходов < ПОТОЛОК_ХОДОВ) {
    const кто = игра.ктоХодит(партия);
    const ответ = игра.ходБота(партия, кто, 'обычный');
    if (ответ === 'не его ход') break;   // очередь сломалась — дальше смотреть незачем
    ходов++;
  }
  return ходов;
}

function карт(партия, имя) { return партия.руки[имя].length; }

/* ---------------------------------------------------------------------
   1. Расклад из автопрогона: трое, козырь ♦, 6♣ В♠ / 9♥ 8♣ / 9♠ Д♥
   --------------------------------------------------------------------- */
(function раскладИзПрогона() {
  const руки = [['6♣', 'В♠'], ['9♥', '8♣'], ['9♠', 'Д♥']];
  let круговых = 0;
  for (let место = 0; место < 3; место++) {
    const п = собратьРасклад({ игроков: 3 }, '♦', руки, место);
    const ходов = доигратьБотами(п);
    const где = 'трое, первым ходит место ' + место + ': ';
    проверить(п.завершена, где + 'партия не кончилась за ' + ходов + ' ходов');
    if (!п.поКругу) continue;   // с этого места круг может и не случиться — считаем ниже
    круговых++;
    const счёт = п.повторыПоложений || {};
    const максимум = Math.max.apply(null, Object.keys(счёт).map(function (к) { return счёт[к]; }).concat([0]));
    проверить(максимум === игра.ПОВТОРОВ_ДО_КРУГА,
      где + 'кончилась на ' + максимум + '-м повторе, а надо на ' + игра.ПОВТОРОВ_ДО_КРУГА + '-м');
    const вживых = игра.оставшиеся(п);
    const больше = Math.max.apply(null, вживых.map(function (и) { return карт(п, и); }));
    const тяжёлые = вживых.filter(function (и) { return карт(п, и) === больше; });
    if (тяжёлые.length === вживых.length) {
      проверить(п.ничья === true && п.проигравшие.length === 0, где + 'поровну у всех, а не ничья');
    } else {
      проверить(JSON.stringify(п.проигравшие) === JSON.stringify(тяжёлые),
        где + 'дураки ' + JSON.stringify(п.проигравшие) + ', а больше карт у ' + JSON.stringify(тяжёлые));
      проверить(п.ничья !== true, где + 'есть дурак, а стоит ничья');
    }
    проверить(п.результат === (п.проигравшие.length ? п.проигравшие.join(' и ') : 'ничья'),
      где + 'результат «' + п.результат + '» не сходится с дураками');
  }
  // Хоть с одного места расклад обязан зайти по кругу — ради него проверка и есть.
  проверить(круговых > 0, 'расклад из прогона ни разу не кончился по кругу');
})();

/* ---------------------------------------------------------------------
   2. Исход по кругу: вдвоём, трое, парами, равенство
   --------------------------------------------------------------------- */
function исход(настройки, руки) {
  const п = собратьРасклад(настройки, '♦', руки, 0);
  игра.итогПоКругу(п);
  return п;
}

(function вдвоём() {
  const п = исход({ игроков: 2 }, [['6♣', 'В♠', '7♥'], ['9♥', '8♣']]);
  проверить(п.завершена && п.поКругу === true, 'вдвоём: итог по кругу не записан');
  проверить(JSON.stringify(п.проигравшие) === JSON.stringify([п.игроки[0]]),
    'вдвоём: дурак не тот, у кого больше карт: ' + JSON.stringify(п.проигравшие));
  проверить(п.ничья !== true, 'вдвоём: есть дурак, а стоит ничья');
})();

(function вдвоёмПоровну() {
  const п = исход({ игроков: 2 }, [['6♣', 'В♠'], ['9♥', '8♣']]);
  проверить(п.ничья === true && п.проигравшие.length === 0 && п.результат === 'ничья',
    'вдвоём поровну: должна быть ничья без дурака');
})();

(function троеДваТяжёлых() {
  const п = исход({ игроков: 3 }, [['6♣', 'В♠'], ['9♥', '8♣'], ['9♠']]);
  проверить(JSON.stringify(п.проигравшие) === JSON.stringify([п.игроки[0], п.игроки[1]]),
    'трое, поровну у двух тяжёлых: дураками должны быть оба, а не ' + JSON.stringify(п.проигравшие));
  проверить(п.ничья !== true, 'трое, поровну у двух: это не ничья');
})();

(function троеОдинТяжёлый() {
  const п = исход({ игроков: 3 }, [['6♣'], ['9♥', '8♣', 'Д♥'], ['9♠']]);
  проверить(JSON.stringify(п.проигравшие) === JSON.stringify([п.игроки[1]]),
    'трое: дурак один, у кого больше всех карт, а не ' + JSON.stringify(п.проигравшие));
})();

(function парами() {
  // Пары: места 0 и 2 против 1 и 3. Сумма первой пары 3, второй — 4.
  const п = исход({ игроков: 4, парами: true }, [['6♣', 'В♠'], ['9♥'], ['7♣'], ['8♣', 'Д♥', 'К♥']]);
  проверить(п.парами === true, 'парами: партия собралась не парной');
  проверить(JSON.stringify(п.проигравшие) === JSON.stringify([п.игроки[1], п.игроки[3]]),
    'парами: дураки не пара с большей суммой карт: ' + JSON.stringify(п.проигравшие));
})();

(function парамиПоровну() {
  const п = исход({ игроков: 4, парами: true }, [['6♣', 'В♠'], ['9♥'], ['7♣'], ['8♣', 'Д♥']]);
  проверить(п.ничья === true && п.проигравшие.length === 0, 'парами поровну: должна быть ничья');
})();

/* ---------------------------------------------------------------------
   3. Счётчик: пока колода не пуста — пуст; запись старой версии читается
   --------------------------------------------------------------------- */
(function счётчикИЗапись() {
  const п = игра.создатьПартию({ игроков: 2 });
  проверить(п.поКругу === false && JSON.stringify(п.повторыПоложений) === '{}',
    'новая партия: счётчик круга не пуст или поКругу не false');

  const запись = игра.собратьЗаписьПартии(п, 0);
  проверить(запись.повторыПоложений && typeof запись.повторыПоложений === 'object',
    'запись партии без счётчика круга');

  const старая = JSON.parse(JSON.stringify(запись));
  delete старая.повторыПоложений;
  delete старая.поКругу;
  const прочитано = игра.разобратьЗаписьПартии(JSON.stringify(старая));
  проверить(прочитано !== null, 'старая запись без полей круга не читается');
  if (прочитано) {
    проверить(JSON.stringify(прочитано.партия.повторыПоложений) === '{}' &&
              прочитано.партия.поКругу === false,
      'старая запись: счётчик не пуст или поКругу не false');
  }

  const сосчётом = JSON.parse(JSON.stringify(запись));
  сосчётом.повторыПоложений = { 'а': 2, 'б': 'мусор' };
  const второе = игра.разобратьЗаписьПартии(JSON.stringify(сосчётом));
  проверить(второе !== null && JSON.stringify(второе.партия.повторыПоложений) === '{"а":2}',
    'запись со счётчиком: счётчик прочитан неверно');
})();

console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
process.exit(провалов > 0 ? 1 : 0);
