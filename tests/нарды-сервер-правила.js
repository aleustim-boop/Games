function проверитьРаздачу(Игра, вариант) {
  console.log('\n--- Раздача, вариант «' + вариант + '» ---');
  const партия = накрытьСтол(Игра, вариант);
  const видБелых = Игра.видДляИгрока(партия, БЕЛЫЕ_МЕСТО, {});
  const видЧёрных = Игра.видДляИгрока(партия, ЧЁРНЫЕ_МЕСТО, {});

  проверить(видБелых.игра === 'нарды', вариант + ': игра называется «нарды»');
  проверить(видБелых.вариант === вариант, вариант + ': вариант нард доехал до игрока');
  проверить(видБелых.мойЦвет === 'белые' && видЧёрных.мойЦвет === 'чёрные',
    вариант + ': начинающий сел белыми, второй — чёрными');
  проверить(видБелых.яХожу === true && видЧёрных.яХожу === false,
    вариант + ': первый ход у белых');
  проверить(видБелых.бросок === null && видБелых.кубикиОсталось.length === 0,
    вариант + ': кубики ещё не брошены');
  проверить(видБелых.завершена === false && видБелых.итог === undefined,
    вариант + ': итога у начатой партии нет');
  проверить(видБелых.креслоСоперника === 2 && видЧёрных.креслоСоперника === 1,
    вариант + ': кресло соперника названо номером');
  проверить(видБелых.застолом === undefined,
    вариант + ': у стола на двоих списка мест нет вовсе');

  /* Расстановка обязана быть той же, что у правил: сервер её не выдумывает. */
  const своя = Правила.создатьПартию({ вид: вариант, первый: Правила.БЕЛЫЕ });
  проверить(Правила.отпечатокПозиции(доскаИзВида(видБелых)) === Правила.отпечатокПозиции(своя),
    вариант + ': расстановка ровно такая, какую делают правила');

  осмотретьВид(видБелых, вариант + ', раздача, белые');
  осмотретьВид(видЧёрных, вариант + ', раздача, чёрные');

  /* Реванш: комната зовёт «раздать» второй раз, называя начинающим того,
     кто в прошлый раз проиграл, — то есть теперь это может быть место,
     сидевшее чёрными. Цвета обязаны поменяться (проигравший садится
     белыми и ходит первым), а кресла за столом — нет: список игроков
     приходит тем же, каким его прислала комната. */
  const реванш = Игра.раздать(ЧЁРНЫЕ_МЕСТО, {
    игроки: [БЕЛЫЕ_МЕСТО, ЧЁРНЫЕ_МЕСТО],
    вариантНард: вариант
  });
  const видРеваншаЧёрногоМеста = Игра.видДляИгрока(реванш, ЧЁРНЫЕ_МЕСТО, {});
  const видРеваншаБелогоМеста = Игра.видДляИгрока(реванш, БЕЛЫЕ_МЕСТО, {});
  проверить(видРеваншаЧёрногоМеста.мойЦвет === 'белые' && видРеваншаЧёрногоМеста.яХожу === true,
    вариант + ': реванш — прошлый проигравший (место «' + ЧЁРНЫЕ_МЕСТО +
    '») садится белыми и ходит первым');
  проверить(видРеваншаБелогоМеста.мойЦвет === 'чёрные' && видРеваншаБелогоМеста.яХожу === false,
    вариант + ': реванш — прошлый победитель садится чёрными');
  проверить(видРеваншаЧёрногоМеста.креслоСоперника === 1 && видРеваншаБелогоМеста.креслоСоперника === 2,
    вариант + ': реванш — кресла за столом те же самые, поменялись только цвета');
  осмотретьВид(видРеваншаЧёрногоМеста, вариант + ', реванш');

  /* Компанией нарды не играют, но прихожая у стола бывает: проверяем,
     что список мест уходит без внутренних имён и с цветом. */
  const видВКомпании = Игра.видДляИгрока(партия, БЕЛЫЕ_МЕСТО, {
    места: [
      { ключ: БЕЛЫЕ_МЕСТО, номер: 1, имя: 'Аня', хозяин: true, наСвязи: true },
      { ключ: ЧЁРНЫЕ_МЕСТО, номер: 2, имя: 'Витя', хозяин: false, наСвязи: true }
    ],
    мест: 2, мойНомер: 1, яХозяин: true, можноНачать: true
  });
  проверить(Array.isArray(видВКомпании.застолом) && видВКомпании.застолом.length === 2 &&
    видВКомпании.застолом[0].цвет === 'белые' && видВКомпании.застолом[1].цвет === 'чёрные',
    вариант + ': в прихожей у каждого места виден цвет');
  осмотретьВид(видВКомпании, вариант + ', прихожая');
}

