function сыгратьПартию(Игра, вариант) {
  console.log('\n--- Партия до победы, вариант «' + вариант + '» ---');
  const партия = накрытьСтол(Игра, вариант);

  let ходов = 0;
  let пропусков = 0;
  let попытокСтарымХодом = 0;   // ход, посчитанный для другой позиции
  let отказовНаСтарыйХод = 0;
  let плохихВидов = 0;
  let несошедшихсяДосок = 0;
  let тупиковБелых = 0;         // сколько раз белым (ходящим) реально нечем было ходить
  let чужойТупикУЖдущего = 0;   // соперник увидел вид.ходитьНечем === true не в свой ход
  let старыйХод = null;         // шаги, законные когда-то, но не сейчас
  let сверокБроска = 0;         // раз проверено, что ждущий видит бросок соперника в последнийХод

  while (!партия.завершена && ходов < ПРЕДОХРАНИТЕЛЬ) {
    const место = Игра.чейХод(партия);
    if (место === null) break;

    if (место === ЧЁРНЫЕ_МЕСТО) {
      /* Бот: и бросок, и ход одним вызовом — так его зовёт комната. */
      const сделано = Игра.ходЗаБота(партия, ЧЁРНЫЕ_МЕСТО, 'лёгкий');
      if (!сделано) { плохихВидов++; break; }
      if (сделано.событие === 'пропуск') пропусков++;

      /* Бот бросает и ходит одним вызовом, так что «свой бросок до хода»
         тестовому коду взять неоткуда — сверяем то, что реально доехало
         до ждущего человека: непустой массив честных костей. */
      const видЖдущегоБота = Игра.видДляИгрока(партия, БЕЛЫЕ_МЕСТО, {});
      проверить(похожеНаБросок(видЖдущегоБота.последнийХод && видЖдущегоБота.последнийХод.бросок),
        вариант + ': ждущий человек видит бросок бота в последнийХод (' +
        JSON.stringify(видЖдущегоБота.последнийХод && видЖдущегоБота.последнийХод.бросок) + ')');
      сверокБроска++;

      ходов++;
      continue;
    }

    /* Человек. Сперва бросок отдельным действием. */
    const брошено = Игра.сделатьХод(партия, БЕЛЫЕ_МЕСТО, { действие: 'бросить' });
    if (!брошено.принято) { плохихВидов++; break; }

    const вид = Игра.видДляИгрока(партия, БЕЛЫЕ_МЕСТО, {});
    if (вид.бросок === null || вид.бросок.length !== 2) плохихВидов++;
    const доска = доскаИзВида(вид);
    if (Правила.целостность(доска) !== null) плохихВидов++;

    /* Ход, посчитанный для ДРУГОЙ позиции. Берём ход прошлого раза и,
       если правила его сейчас не признают, шлём серверу: он обязан
       отказать. Если вдруг признают — случай не считаем и ждём другого
       (сколько таких попыток вышло, проверяется в конце: ноль попыток —
       это провал, а не пропуск). */
    if (старыйХод && !ходЗаконен(доска, старыйХод)) {
      попытокСтарымХодом++;
      const было = отпечатокСтола(вид);
      const ответ = Игра.сделатьХод(партия, БЕЛЫЕ_МЕСТО, { действие: 'ход', шаги: старыйХод });
      const послеОтказа = отпечатокСтола(Игра.видДляИгрока(партия, БЕЛЫЕ_МЕСТО, {}));
      if (!ответ.принято && типичныйОтказ(ответ) && послеОтказа === было) отказовНаСтарыйХод++;
    }

    if (вид.ходитьНечем) {
      /* Пустой бросок у ходящего — самый частый случай спутать «моё поле
         истины» с чужим: у ждущего игрока свежего броска нет вовсе, и
         ходитьНечем у него обязано быть false, что бы ни выпало ходящему. */
      тупиковБелых++;
      const видЖдущего = Игра.видДляИгрока(партия, ЧЁРНЫЕ_МЕСТО, {});
      if (видЖдущего.ходитьНечем !== false) чужойТупикУЖдущего++;

      /* Пустой список шагов — законный пропуск. */
      const ответ = Игра.сделатьХод(партия, БЕЛЫЕ_МЕСТО, { действие: 'ход', шаги: [] });
      if (!ответ.принято || ответ.событие !== 'пропуск') плохихВидов++;

      /* Пропустил ходить нечем — соперник обязан увидеть тот же бросок,
         который белым оказался бессилен, а не «ничего не было». */
      const видЖдущегоПослеПропуска = Игра.видДляИгрока(партия, ЧЁРНЫЕ_МЕСТО, {});
      проверить(похожеНаБросок(видЖдущегоПослеПропуска.последнийХод && видЖдущегоПослеПропуска.последнийХод.бросок) &&
        JSON.stringify(видЖдущегоПослеПропуска.последнийХод.бросок) === JSON.stringify(вид.бросок),
        вариант + ': ждущий видит бросок белых, с которым те пропустили ход (' + JSON.stringify(вид.бросок) + ')');
      сверокБроска++;

      пропусков++;
      ходов++;
      continue;
    }

    const выбран = случайныйЗаконныйХод(доска);
    if (!выбран) { плохихВидов++; break; }
    const шаги = шагиДляОтправки(выбран);
    старыйХод = шаги;

    /* Как будет считать браузер: применяем свой же ход к своей копии
       и потом сверяем доску с той, что пришлёт сервер. */
    const своя = Правила.копияПартии(доска);
    Правила.сделатьХод(своя, { шаги: шаги });

    const ответ = Игра.сделатьХод(партия, БЕЛЫЕ_МЕСТО, { действие: 'ход', шаги: шаги });
    if (!ответ.принято) { плохихВидов++; break; }

    const послеХода = Игра.видДляИгрока(партия, БЕЛЫЕ_МЕСТО, {});
    if (Правила.отпечатокПозиции(доскаИзВида(послеХода)) !== Правила.отпечатокПозиции(своя)) {
      несошедшихсяДосок++;
    }
    if (!послеХода.последнийХод || послеХода.последнийХод.мой !== true ||
        послеХода.последнийХод.чей !== 'белые' ||
        послеХода.последнийХод.шаги.length !== шаги.length) {
      плохихВидов++;
    }

    /* Ждущий (чёрные) обязан увидеть ровно тот бросок, каким белые только
       что сходили, — тот же самый, что был у белых в вид.бросок до хода. */
    const видЖдущегоПослеХода = Игра.видДляИгрока(партия, ЧЁРНЫЕ_МЕСТО, {});
    проверить(похожеНаБросок(видЖдущегоПослеХода.последнийХод && видЖдущегоПослеХода.последнийХод.бросок) &&
      JSON.stringify(видЖдущегоПослеХода.последнийХод.бросок) === JSON.stringify(вид.бросок),
      вариант + ': ждущий видит бросок белых, с которым те сходили (' + JSON.stringify(вид.бросок) + ')');
    сверокБроска++;

    ходов++;
  }

  const видБелых = Игра.видДляИгрока(партия, БЕЛЫЕ_МЕСТО, {});
  const видЧёрных = Игра.видДляИгрока(партия, ЧЁРНЫЕ_МЕСТО, {});

  проверить(партия.завершена === true, вариант + ': партия доиграна до победы (ходов ' + ходов + ')');
  проверить(ходов < ПРЕДОХРАНИТЕЛЬ, вариант + ': партия уложилась в предохранитель');
  проверить(плохихВидов === 0, вариант + ': по дороге ни одного сбоя вида или хода');
  проверить(несошедшихсяДосок === 0, вариант + ': доска сервера совпала с просчитанной после каждого хода');
  проверить(чужойТупикУЖдущего === 0,
    вариант + ': у ждущего игрока ходитьНечем === false даже при пустом броске у ходящего');

  проверить(видБелых.итог && видЧёрных.итог, вариант + ': итог пришёл обоим');
  if (видБелых.итог && видЧёрных.итог) {
    проверить(видБелых.итог.яВыиграл !== видЧёрных.итог.яВыиграл,
      вариант + ': выиграл ровно один');
    проверить(видБелых.итог.цена >= 1 && видБелых.итог.цена <= 3,
      вариант + ': цена победы от 1 до 3 (пришла ' + видБелых.итог.цена + ', ' +
      видБелых.итог.видПобеды + ')');
    проверить(видБелых.итог.победитель === 'белые' || видБелых.итог.победитель === 'чёрные',
      вариант + ': победитель назван цветом');
    проверить(typeof видБелых.итог.причина === 'string' && видБелых.итог.причина.length > 0,
      вариант + ': причина конца написана словами');
  }
  проверить(партия.результат === БЕЛЫЕ_МЕСТО || партия.результат === ЧЁРНЫЕ_МЕСТО,
    вариант + ': комната увидит победителя в поле «результат»');
  проверить(партия.проигравшие.length === 1 && партия.проигравшие[0] !== партия.результат,
    вариант + ': проигравший записан ровно один');
  проверить(видБелых.завершена === true && видБелых.чейХод === null,
    вариант + ': у законченной партии хода ни у кого нет');
  проверить(Игра.чейХод(партия) === null, вариант + ': комнате тоже никто не ходит');

  осмотретьВид(видБелых, вариант + ', конец партии, белые');
  осмотретьВид(видЧёрных, вариант + ', конец партии, чёрные');

  /* Бросок и ход после конца партии. */
  const броскоПослеКонца = Игра.сделатьХод(партия, БЕЛЫЕ_МЕСТО, { действие: 'бросить' });
  проверить(!броскоПослеКонца.принято && типичныйОтказ(броскоПослеКонца),
    вариант + ': бросок после конца партии отвергнут словами («' + броскоПослеКонца.причина + '»)');
  const ходПослеКонца = Игра.сделатьХод(партия, БЕЛЫЕ_МЕСТО, {
    действие: 'ход', шаги: [{ откуда: 13, куда: 12, кубик: 1 }]
  });
  проверить(!ходПослеКонца.принято && типичныйОтказ(ходПослеКонца),
    вариант + ': ход после конца партии отвергнут словами («' + ходПослеКонца.причина + '»)');
  проверить(Игра.ходЗаБота(партия, ЧЁРНЫЕ_МЕСТО, 'лёгкий') === null,
    вариант + ': бот в законченной партии не ходит');

  /* Ход из другой позиции — ноль попыток считаем провалом: проверка,
     которой не досталось ни одного случая, ничего не доказала. */
  проверить(попытокСтарымХодом > 0,
    вариант + ': случаи «ход посчитан для другой позиции» встретились (' + попытокСтарымХодом + ')');
  проверить(отказовНаСтарыйХод === попытокСтарымХодом,
    вариант + ': все ходы из другой позиции отвергнуты словами (' +
    отказовНаСтарыйХод + ' из ' + попытокСтарымХодом + ')');

  /* Ноль сверенных бросков — проверка ничего не доказала, это провал. */
  проверить(сверокБроска > 0,
    вариант + ': бросок ходившего доехал до ждущего хотя бы раз (' + сверокБроска + ')');

  return { пропусков: пропусков, ходов: ходов, тупиковБелых: тупиковБелых };
}

/** Отказ ли это и написан ли он словами, понятными человеку. */
function типичныйОтказ(ответ) {
  return ответ && ответ.принято === false &&
         typeof ответ.причина === 'string' && ответ.причина.trim().length >= 5;
}

/* =====================================================================
   ЧАСТЬ 3. ОТКАЗЫ — то, во что сервер не должен поверить
   ===================================================================== */

function проверитьОтказы(Игра) {
  console.log('\n--- Отказы: присланному не верим ---');
  const партия = накрытьСтол(Игра, 'короткие');

  /* Один общий приём: пробуем незаконное и смотрим два раза — отказали ли
     словами и осталась ли доска той же. */
  function незаконно(название, ктоЯ, намерение) {
    const было = отпечатокСтола(Игра.видДляИгрока(партия, БЕЛЫЕ_МЕСТО, {}));
    const ответ = Игра.сделатьХод(партия, ктоЯ, намерение);
    const стало = отпечатокСтола(Игра.видДляИгрока(партия, БЕЛЫЕ_МЕСТО, {}));
    проверить(типичныйОтказ(ответ), название + ' — отказ словами' +
      (ответ && ответ.причина ? ' («' + ответ.причина + '»)' : ' (приняли!)'));
    проверить(стало === было, название + ' — доска и кубики не тронуты');
  }

  незаконно('чёрные бросают в чужой ход', ЧЁРНЫЕ_МЕСТО, { действие: 'бросить' });
  незаконно('чёрные ходят в чужой ход', ЧЁРНЫЕ_МЕСТО,
    { действие: 'ход', шаги: [{ откуда: 12, куда: 11, кубик: 1 }] });
  незаконно('ход до броска кубиков', БЕЛЫЕ_МЕСТО,
    { действие: 'ход', шаги: [{ откуда: 13, куда: 12, кубик: 1 }] });
  незаконно('незнакомое действие', БЕЛЫЕ_МЕСТО, { действие: 'взять-козыря' });
  незаконно('чужак за доской', 'бот-3', { действие: 'бросить' });

  const брошено = Игра.сделатьХод(партия, БЕЛЫЕ_МЕСТО, { действие: 'бросить' });
  проверить(брошено.принято && брошено.событие === 'бросок', 'белые бросили кубики');

  const вид = Игра.видДляИгрока(партия, БЕЛЫЕ_МЕСТО, {});
  проверить(Array.isArray(вид.бросок) && вид.бросок.length === 2 &&
    вид.бросок.every(function (к) { return к >= 1 && к <= 6; }),
    'бросок пришёл двумя числами от 1 до 6 (' + JSON.stringify(вид.бросок) + ')');
  проверить(вид.максимумКубиков > 0 && вид.ходитьНечем === false,
    'в начальной позиции ходить есть чем');
  осмотретьВид(вид, 'после броска');

  незаконно('второй бросок подряд', БЕЛЫЕ_МЕСТО, { действие: 'бросить' });

  /* Чужая шашка и пустой пункт — ищем их на доске, а не выписываем
     числами: расстановка коротких и длинных разная, а беда одна. */
  const доска = доскаИзВида(вид);
  let чужойПункт = 0;
  let пустойПункт = 0;
  for (let п = 1; п <= Правила.ПУНКТОВ; п++) {
    const стопка = Правила.пункт(доска, п);
    if (!стопка.сколько && !пустойПункт) пустойПункт = п;
    if (стопка.сколько && стопка.цвет === 'чёрные' && !чужойПункт) чужойПункт = п;
  }
  проверить(чужойПункт > 0 && пустойПункт > 0,
    'на доске нашлись чужой пункт (' + чужойПункт + ') и пустой (' + пустойПункт + ')');

  незаконно('чужой шашкой', БЕЛЫЕ_МЕСТО, {
    действие: 'ход',
    шаги: [{ откуда: чужойПункт, куда: чужойПункт > 1 ? чужойПункт - 1 : чужойПункт + 1 }]
  });
  незаконно('с пустого пункта', БЕЛЫЕ_МЕСТО, {
    действие: 'ход',
    шаги: [{ откуда: пустойПункт, куда: пустойПункт > 1 ? пустойПункт - 1 : пустойПункт + 1 }]
  });
  незаконно('пустой ход, когда ходить есть чем', БЕЛЫЕ_МЕСТО, { действие: 'ход', шаги: [] });
  незаконно('мусор вместо списка шагов', БЕЛЫЕ_МЕСТО, { действие: 'ход', шаги: 'всё сразу' });
  /* Мусор внутри самого перемещения: каждое из этих значений «очиститьШаги»
     обязана отбить ещё до того, как ход дойдёт до правил. */
  незаконно('откуда — отрицательное число', БЕЛЫЕ_МЕСТО, {
    действие: 'ход', шаги: [{ откуда: -1, куда: 12 }]
  });
  незаконно('куда — дробное число', БЕЛЫЕ_МЕСТО, {
    действие: 'ход', шаги: [{ откуда: 13, куда: 12.5 }]
  });
  незаконно('откуда — не число (NaN)', БЕЛЫЕ_МЕСТО, {
    действие: 'ход', шаги: [{ откуда: NaN, куда: 12 }]
  });
  незаконно('откуда — объект вместо номера пункта', БЕЛЫЕ_МЕСТО, {
    действие: 'ход', шаги: [{ откуда: {}, куда: 12 }]
  });
  незаконно('кубик больше шести граней', БЕЛЫЕ_МЕСТО, {
    действие: 'ход', шаги: [{ откуда: 13, куда: 12, кубик: 7 }]
  });
  незаконно('кубик ноль', БЕЛЫЕ_МЕСТО, {
    действие: 'ход', шаги: [{ откуда: 13, куда: 12, кубик: 0 }]
  });
  незаконно('пункта с таким номером нет', БЕЛЫЕ_МЕСТО, {
    действие: 'ход', шаги: [{ откуда: 99, куда: 3, кубик: 1 }]
  });
  незаконно('перемещений больше, чем бывает', БЕЛЫЕ_МЕСТО, {
    действие: 'ход',
    шаги: [
      { откуда: 13, куда: 12 }, { откуда: 13, куда: 12 },
      { откуда: 13, куда: 12 }, { откуда: 13, куда: 12 }, { откуда: 13, куда: 12 }
    ]
  });

  /* Отдельно: отказ на чужую шашку должен объяснять, ЧТО не так. */
  const проЧужую = Игра.сделатьХод(партия, БЕЛЫЕ_МЕСТО, {
    действие: 'ход',
    шаги: [{ откуда: чужойПункт, куда: чужойПункт > 1 ? чужойПункт - 1 : чужойПункт + 1 }]
  });
  проверить(!проЧужую.принято && /соперник/i.test(проЧужую.причина || ''),
    'отказ на чужую шашку называет причину («' + (проЧужую.причина || '') + '»)');

  /* Кубики от игрока не принимаются: двадцать столов просят дубль 6-6. */
  let разДубльШесть = 0;
  for (let i = 0; i < СТОЛОВ_НА_КУБИКИ; i++) {
    const свой = накрытьСтол(Игра, 'короткие');
    Игра.сделатьХод(свой, БЕЛЫЕ_МЕСТО, { действие: 'бросить', кубики: [6, 6] });
    const бросок = Игра.видДляИгрока(свой, БЕЛЫЕ_МЕСТО, {}).бросок;
    if (бросок && бросок[0] === 6 && бросок[1] === 6) разДубльШесть++;
  }
  проверить(разДубльШесть <= 2,
    'присланные кубики не принимаются: 6-6 выпало ' + разДубльШесть + ' раз из ' + СТОЛОВ_НА_КУБИКИ);
}

/* =====================================================================
   ЧАСТЬ 4. СДАЧА
   ===================================================================== */

function проверитьСдачу(Игра) {
  console.log('\n--- Сдача ---');
  const партия = накрытьСтол(Игра, 'короткие');
  Игра.сделатьХод(партия, БЕЛЫЕ_МЕСТО, { действие: 'бросить' });

  /* Сдаётся тот, кто нажал кнопку, а не тот, чей ход: сдаём чёрными,
     хотя сейчас ходят белые. */
  const ответ = Игра.сделатьХод(партия, ЧЁРНЫЕ_МЕСТО, { действие: 'сдаться' });
  проверить(ответ.принято && ответ.событие === 'сдался', 'сдаться можно и не в свой ход');

  const видБелых = Игра.видДляИгрока(партия, БЕЛЫЕ_МЕСТО, {});
  const видЧёрных = Игра.видДляИгрока(партия, ЧЁРНЫЕ_МЕСТО, {});
  проверить(видБелых.завершена === true && видБелых.итог && видБелых.итог.яВыиграл === true,
    'сдача: соперник сдавшегося выиграл');
  проверить(видЧёрных.итог && видЧёрных.итог.яВыиграл === false &&
    видЧёрных.итог.победитель === 'белые', 'сдача: сдавшийся проиграл белым');
  проверить(видБелых.итог.цена === 1, 'сдача стоит одно очко, а не марс');
  проверить(партия.результат === БЕЛЫЕ_МЕСТО && партия.проигравшие[0] === ЧЁРНЫЕ_МЕСТО,
    'сдача: комната увидит победителя и проигравшего');
  осмотретьВид(видБелых, 'после сдачи');

  const ещёРаз = Игра.сделатьХод(партия, ЧЁРНЫЕ_МЕСТО, { действие: 'сдаться' });
  проверить(типичныйОтказ(ещёРаз), 'вторая сдача отвергнута словами («' + ещёРаз.причина + '»)');
  const текст = Игра.текстСобытия({ что: 'сдался', кто: ЧЁРНЫЕ_МЕСТО, имя: 'Витя' }, БЕЛЫЕ_МЕСТО, [], false);
  проверить(typeof текст === 'string' && текст.length > 0 && текст.indexOf(ЧЁРНЫЕ_МЕСТО) === -1,
    'событие сдачи рассказано словами без внутренних имён («' + текст + '»)');
}

/* =====================================================================
   ЧАСТЬ 5. ДОГОВОР ИГРЫ ДЛЯ СЕРВЕРА
   ===================================================================== */

function проверитьДоговор(Игра) {
  console.log('\n--- Договор игры для сервера ---');
  const реестр = require(path.join(КОРЕНЬ, 'server', 'игры', 'реестр.js'));
  let беда = '';
  try { реестр.проверитьДоговор(Игра, 'server/игры/нарды.js'); }
  catch (сбой) { беда = сбой.message; }
  проверить(беда === '', 'реестр принимает договор игры' + (беда ? ': ' + беда : ''));
  проверить(Игра.имя === 'нарды', 'игра называется «нарды»');
  проверить(Игра.мест.мин === 2 && Игра.мест.макс === 2, 'мест за доской ровно два');
  проверить(Игра.напарник([БЕЛЫЕ_МЕСТО, ЧЁРНЫЕ_МЕСТО], БЕЛЫЕ_МЕСТО, 2) === null,
    'напарников в нардах нет');
  проверить(Игра.ходВнеОчереди === null, 'хода вне очереди в нардах не бывает');
  проверить(Игра.знаки.сколько() === 0 && Игра.знаки.этоЗнак(1) === false,
    'знаков внимания у нард пока нет, и об этом сказано честно');

  ['бросок', 'ход', 'пропуск', 'сдался', 'вошёл', 'ушёл', 'пропал'].forEach(function (что) {
    const текст = Игра.текстСобытия({ что: что, кто: ЧЁРНЫЕ_МЕСТО, имя: 'Витя' }, БЕЛЫЕ_МЕСТО, [], false);
    проверить(typeof текст === 'string' && текст.trim().length > 0 &&
      текст.indexOf(ЧЁРНЫЕ_МЕСТО) === -1,
      'событие «' + что + '» рассказано словами («' + текст + '»)');
  });
}

/* =====================================================================
   ПРОГОН ЦЕЛИКОМ
   ===================================================================== */

/** Всё, что можно спросить у модуля без сети. Возвращает счёт пропусков. */
function прогнать(Игра, толькоОтказы) {
  проверитьДоговор(Игра);
  проверитьОтказы(Игра);
  if (толькоОтказы) return;

  проверитьРаздачу(Игра, 'короткие');
  проверитьРаздачу(Игра, 'длинные');
  проверитьСдачу(Игра);

  const короткая = сыгратьПартию(Игра, 'короткие');
  const длинная = сыгратьПартию(Игра, 'длинные');

  console.log('\n--- Пропуск хода, когда ходить нечем ---');
  проверить(короткая.пропусков + длинная.пропусков > 0,
    'случаи «ходить нечем» встретились и прошли пропуском (' +
    (короткая.пропусков + длинная.пропусков) + ')');
  /* Ноль случаев — это провал, а не пропуск: без них проверка «у ждущего
     ходитьНечем всегда false» никогда не сработала бы по-настоящему. */
  проверить(короткая.тупиковБелых + длинная.тупиковБелых > 0,
    'случаи «нечем ходить именно у белых» встретились (' +
    (короткая.тупиковБелых + длинная.тупиковБелых) + ')');
}

function напечататьИтог() {
  console.log('\nИтого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
}

/* ---------------------------------------------------------------------
   ОБЫЧНЫЙ ЗАПУСК
   --------------------------------------------------------------------- */
function обычныйЗапуск() {
  console.log('=== Нарды для сервера: партия играется, незаконное отвергается ===');
  поставитьЗерно(ЗЕРНО);
  const Игра = require(ПУТЬ_ИГРЫ);
  прогнать(Игра, false);
  напечататьИтог();

  if (всегоПроверок === 0) {
    console.log('ПЛОХО: не сделано ни одной проверки — она смотрит не туда');
    process.exitCode = 1;
    return;
  }
  if (провалов > 0) process.exitCode = 1;
  else console.log('Сервер играет в нарды по правилам и присланному не верит.');
}

/**
 * Найти позицию, где ходить нечем именно белым (ходящим) — играя НАСТОЯЩИМ,
 * непорченым модулем короткую партию. Нужна ломающему прогону, чтобы
 * проверить регрессию пункта 1 (гейт «вид.яХожу») без розыгрыша полной
 * партии на порченой копии: там доска вообще не двигается (правила не
 * зовутся), и тупиковая позиция никогда не наступит.
 *
 * Несколько попыток подряд со своим зерном на каждую — тупик встречается
 * не в любой партии, а перебор коротких партий делает поиск быстрым и всё
 * равно воспроизводимым слово в слово при каждом запуске.
 */
function найтиТупиковуюПозицию(ИграНастоящая) {
  for (let попытка = 0; попытка < 20; попытка++) {
    поставитьЗерно(ЗЕРНО + попытка);
    const партия = накрытьСтол(ИграНастоящая, 'короткие');
    for (let ходов = 0; ходов < ПРЕДОХРАНИТЕЛЬ && !партия.завершена; ходов++) {
      const место = ИграНастоящая.чейХод(партия);
      if (место === null) break;
      if (место === ЧЁРНЫЕ_МЕСТО) {
        const сделано = ИграНастоящая.ходЗаБота(партия, ЧЁРНЫЕ_МЕСТО, 'лёгкий');
        if (!сделано) break;
        continue;
      }
      ИграНастоящая.сделатьХод(партия, БЕЛЫЕ_МЕСТО, { действие: 'бросить' });
      const вид = ИграНастоящая.видДляИгрока(партия, БЕЛЫЕ_МЕСТО, {});
      if (вид.ходитьНечем) return Правила.копияПартии(доскаИзВида(вид));
      const доска = доскаИзВида(вид);
      const выбран = случайныйЗаконныйХод(доска);
      if (!выбран) break;
      ИграНастоящая.сделатьХод(партия, БЕЛЫЕ_МЕСТО, { действие: 'ход', шаги: шагиДляОтправки(выбран) });
    }
  }
  return null;
}

/* ---------------------------------------------------------------------
   ЛОМАЮЩИЙ ЗАПУСК: портим КОПИЮ модуля во временной папке.
   Файл проекта не трогаем и не откатываем — в нём может лежать чужая
   несохранённая работа.
   --------------------------------------------------------------------- */
function ломающийЗапуск() {
  console.log('=== Ломающий запуск: в копии модуля ход больше не проверяется правилами ===\n');
  поставитьЗерно(ЗЕРНО);

  const исходник = fs.readFileSync(ПУТЬ_ИГРЫ, 'utf8');

  /* 1. Настоящая поломка: «сыгратьХод» верит присланным перемещениям
        вместо того, чтобы переспросить правила. */
  const былаПроверка = 'const сделанные = Правила.сделатьХод(партия.доска, { шаги: шаги });';
  const сталоДоверие = 'const сделанные = шаги.map(function (ш) {\n' +
    '    return { фишка: \'б1\', откуда: ш.откуда, куда: ш.куда,\n' +
    '             кубик: ш.кубик || 1, побита: null, вынос: ш.куда === \'вне\' };\n' +
    '  });';
  if (исходник.indexOf(былаПроверка) === -1) {
    console.log('ПЛОХО: в модуле не нашлась проверка хода правилами — ломать нечего.');
    console.log('       Искали строку: ' + былаПроверка);
    process.exitCode = 1;
    return;
  }
  let порченый = исходник.split(былаПроверка).join(сталоДоверие);

  /* 2. Вторая, независимая поломка: регрессия пункта 1 ревью — вид.ходитьНечем
        снова не смотрит, чей сейчас ход, и у ждущего игрока тоже true. */
  const былГейтХода = 'вид.ходитьНечем = вид.яХожу && Boolean(снимок.бросок) && снимок.максимумКубиков === 0;';
  const сталоБезГейта = 'вид.ходитьНечем = Boolean(снимок.бросок) && снимок.максимумКубиков === 0;';
  if (порченый.indexOf(былГейтХода) === -1) {
    console.log('ПЛОХО: в модуле не нашлась строка вид.ходитьНечем — ломать нечего.');
    console.log('       Искали строку: ' + былГейтХода);
    process.exitCode = 1;
    return;
  }
  порченый = порченый.split(былГейтХода).join(сталоБезГейта);

  /* 3. Третья, независимая поломка: бросок ходившего теряется при записи
        последнего хода — ждущий игрок больше не узнает, с чем соперник
        сходил или пропустил. Число замен обязано быть ровно одно: ноль
        значит нечего ломать, больше одного — замена задела не то место. */
  const былБросокВХоде = '    запись: Правила.записьХода({ шаги: сделанные }),\n' +
    '    бросок: броскоДоХода\n' +
    '  };';
  const сталоБезБроскаВХоде = '    запись: Правила.записьХода({ шаги: сделанные })\n' +
    '  };';
  const числоЗаменБроска = порченый.split(былБросокВХоде).length - 1;
  if (числоЗаменБроска !== 1) {
    console.log('ПЛОХО: строка с полем «бросок» в последнийХод нашлась ' +
      числоЗаменБроска + ' раз(а) — должно быть ровно один.');
    console.log('       Искали строку: ' + былБросокВХоде);
    process.exitCode = 2;
    return;
  }
  порченый = порченый.split(былБросокВХоде).join(сталоБезБроскаВХоде);

  /* 4. Копия лежит в другой папке — соседние файлы надо звать по полному
        пути, иначе она просто не загрузится. Это не поломка, а переезд. */
  const переезды = [
    ["require('../../js/нарды-правила.js')", 'require(' + JSON.stringify(ПУТЬ_ПРАВИЛ.replace(/\\/g, '/')) + ')'],
    ["require('../../js/нарды-бот.js')", 'require(' + JSON.stringify(ПУТЬ_БОТА.replace(/\\/g, '/')) + ')']
  ];
  for (const [было, стало] of переезды) {
    if (порченый.indexOf(было) === -1) {
      console.log('ПЛОХО: в модуле не нашлась строка подключения: ' + было);
      process.exitCode = 1;
      return;
    }
    порченый = порченый.split(было).join(стало);
  }

  /* Тупиковую позицию для проверки второй поломки добываем НАСТОЯЩИМ,
     непорченым модулем — на порченой копии доска не двигается, и такая
     позиция там сама никогда не наступит. Поиск сбрасывает Math.random
     на свой отсчёт, поэтому сразу за ним зерно ставится заново: обычные
     проверки отказов должны видеть тот же случайный ряд, что и раньше. */
  const доскаСТупиком = найтиТупиковуюПозицию(require(ПУТЬ_ИГРЫ));
  поставитьЗерно(ЗЕРНО);

  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'нарды-сервер-'));
  const копия = path.join(папка, 'нарды.js');
  try {
    fs.writeFileSync(копия, порченый, 'utf8');
    console.log('  порченая копия: ' + копия + '\n');
    const Порченая = require(копия);
    /* Гоняем только отказы: партия по порченому модулю всё равно не
       поедет, а покраснеть обязано именно «не верим присланному». */
    прогнать(Порченая, true);

    /* Регрессия пункта 1 отдельно: своей партией на порченом модуле её не
       поймать (доска неподвижна), поэтому берём готовую тупиковую позицию
       и спрашиваем вид напрямую — видДляИгрока к «сыгратьХод» не ходит. */
    if (доскаСТупиком) {
      const партияСнимок = {
        игроки: [БЕЛЫЕ_МЕСТО, ЧЁРНЫЕ_МЕСТО], завершена: false, результат: null,
        проигравшие: [], ничья: false,
        цвета: { [БЕЛЫЕ_МЕСТО]: Правила.БЕЛЫЕ, [ЧЁРНЫЕ_МЕСТО]: Правила.ЧЁРНЫЕ },
        доска: доскаСТупиком, последнийХод: null,
        цена: 0, видПобеды: null, причинаКонца: null
      };
      const видЖдущего = Порченая.видДляИгрока(партияСнимок, ЧЁРНЫЕ_МЕСТО, {});
      проверить(видЖдущего.ходитьНечем === false,
        'регрессия пункта 1: у ждущего игрока ходитьНечем в порченой копии');
    } else {
      проверить(false, 'регрессия пункта 1: тупиковая позиция для проверки не нашлась');
    }

    /* Третья поломка отдельно: «сыгратьПартию» сюда не заходит (в ломающем
       прогоне играются только отказы, доска неподвижна), поэтому один ход
       разыгрываем здесь вручную и смотрим, что досталось ждущему. */
    const партияДляБроска = накрытьСтол(Порченая, 'короткие');
    Порченая.сделатьХод(партияДляБроска, БЕЛЫЕ_МЕСТО, { действие: 'бросить' });
    const ходДляБроска = Порченая.сделатьХод(партияДляБроска, БЕЛЫЕ_МЕСТО,
      { действие: 'ход', шаги: [{ откуда: 13, куда: 12, кубик: 1 }] });
    if (ходДляБроска.принято) {
      const видЖдущегоБроска = Порченая.видДляИгрока(партияДляБроска, ЧЁРНЫЕ_МЕСТО, {});
      проверить(похожеНаБросок(видЖдущегоБроска.последнийХод && видЖдущегоБроска.последнийХод.бросок),
        'регрессия «бросок в последнийХод»: у ждущего игрока пришёл массив кубиков в порченой копии');
    } else {
      проверить(false, 'регрессия «бросок в последнийХод»: ход для проверки не приняли (' +
        ходДляБроска.причина + ')');
    }

    напечататьИтог();

    const проЧужую = красные.some(function (слова) { return слова.indexOf('чужой шашкой') !== -1; });
    const проТупик = красные.some(function (слова) { return слова.indexOf('регрессия пункта 1') !== -1; });
    const проБросок = красные.some(function (слова) { return слова.indexOf('бросок в последнийХод') !== -1; });
    if (проЧужую && проТупик && проБросок) {
      console.log('\nЛомающий запуск покраснел, как и должен. Красные пункты:');
      красные.forEach(function (слова) { console.log('   ' + слова); });
    } else {
      if (!проЧужую) console.log('\nПЛОХО: порченый модуль прошёл пункт «чужой шашкой» — проверка смотрит не туда');
      if (!проТупик) console.log('ПЛОХО: порченый модуль прошёл регрессию пункта 1 (вид.ходитьНечем) — проверка смотрит не туда');
      if (!проБросок) console.log('ПЛОХО: порченый модуль прошёл регрессию «бросок в последнийХод» — проверка смотрит не туда');
      process.exitCode = 1;
    }
  } finally {
    /* Прибираем за собой: сначала файл, потом пустую папку. Ничего
       рекурсивного — сносить папки целиком в проекте запрещено. */
    try { fs.unlinkSync(копия); } catch (е) { /* уже нет — и ладно */ }
    try { fs.rmdirSync(папка); } catch (е) { /* уже нет — и ладно */ }
  }
}

if (process.argv.indexOf('--сломать') !== -1) ломающийЗапуск();
else обычныйЗапуск();
