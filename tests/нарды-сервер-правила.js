/* =====================================================================
   НАРДЫ ДЛЯ СЕРВЕРА: ПАРТИЯ ДОИГРЫВАЕТСЯ, А НЕЗАКОННОЕ ОТВЕРГАЕТСЯ

   Что проверяем. Модуль server/игры/нарды.js зовётся НАПРЯМУЮ, без
   сети и без сервера: комната ему тут не нужна, а чем меньше в проверке
   движущихся частей, тем понятнее, кто виноват, когда она покраснеет.

   Проверка отвечает на три вопроса:

     1) ИГРАЕТСЯ ЛИ. Две партии до победы — короткие и длинные. За белых
        играет «человек»: он бросает кубики отдельным действием, а ход
        считает ПО ВИДУ, который ему прислал сервер (вид → снимок доски →
        правила → случайный законный ход). Это ровно то, что будет делать
        браузер, и заодно доказательство, что вида хватает для игры.
        За чёрных играет бот через «ходЗаБота».

     2) НЕ ВЕРИТ ЛИ СЕРВЕР ПРИСЛАННОМУ. Двенадцать попыток сходить
        незаконно: не в свою очередь, чужой шашкой, с пустого пункта,
        второй бросок подряд, ход, посчитанный для другой позиции,
        пустой ход при живых шагах, мусор вместо списка шагов, бросок
        и ход после конца партии. Каждая обязана получить отказ СЛОВАМИ,
        и доска после отказа обязана остаться прежней — до последней
        шашки и до последнего кубика. Отдельно: кубики, присланные
        игроком, не принимаются (двадцать столов подряд просят 6-6).

     3) НЕ УЕЗЖАЕТ ЛИ ЛИШНЕЕ В ВИД. Каждый вид осматривается вглубь:
        ни объекта партии, ни списка игроков, ни цветов по местам, ни
        внутреннего имени места («человек», «бот») в нём быть не должно.

   ПОЧЕМУ СТОРОЖ ПОЛЕЙ (tests/сторож-полей.js) ЗДЕСЬ НЕ ВЗЯТ. Он умеет
   две игры: дурака и шашки, и всё, что не шашки, считает картами —
   требует в ответе «картУСоперника», «вКолоде» и «вОтбое» числами.
   На нардах он даёт три ложных провала (проверено запуском). Чинить
   общий файл проверок — не эта задача (он чужой), поэтому осмотр полей
   здесь свой и короткий, а про сторожа сказано вслух.

   ПОВТОРЯЕМОСТЬ. Math.random подменяется своим генератором с постоянным
   зерном — и сервер (кубики), и бот становятся предсказуемыми: прогон
   повторяется слово в слово, и найденная беда воспроизводится с первого
   раза. Подмена живёт только внутри этого процесса.

   Запуск:
       node tests/нарды-сервер-правила.js

   ЛОМАЮЩИЙ ЗАПУСК (проверка обязана уметь краснеть):
       node tests/нарды-сервер-правила.js --сломать

   Копирует server/игры/нарды.js во временную папку и в КОПИИ заставляет
   «сыгратьХод» поверить присланному: ход больше не переспрашивается у
   правил. Проверка обязана покраснеть на пункте «чужой шашкой». Файл
   проекта при этом не трогается ни на минуту.
   ===================================================================== */

