/* Имена полей, которых в виде для игрока быть не должно ни на каком
   ярусе. Это внутренности партии сервера: объект партии, список мест,
   раскладка цветов по местам, служебные итоги комнаты. */
const ЗАПРЕЩЁННЫЕ_ПОЛЯ = [
  'партия', 'доскаПартии', 'цвета', 'игроки', 'проигравшие', 'результат',
  'причинаКонца', 'ключ', 'кто', 'пропуск', 'токен'
];

/* Внутренние имена мест: их придумывает сервер, и игроку они не нужны
   никогда — он видит номер кресла и имя человека. */
const ИМЕНА_МЕСТ = [БЕЛЫЕ_МЕСТО, ЧЁРНЫЕ_МЕСТО];

/** Осмотреть вид вглубь: нет ли в нём внутренностей сервера. */
function осмотретьВид(вид, откуда) {
  const беды = [];

  (function обход(узел, путь) {
    if (!узел || typeof узел !== 'object') return;
    Object.keys(узел).forEach(function (поле) {
      const где = путь ? путь + '.' + поле : поле;
      if (ЗАПРЕЩЁННЫЕ_ПОЛЯ.indexOf(поле) !== -1) {
        беды.push('поле «' + где + '» — это внутренность сервера');
      }
      const значение = узел[поле];
      if (typeof значение === 'string') {
        ИМЕНА_МЕСТ.forEach(function (имя) {
          if (значение.indexOf(имя) !== -1) {
            беды.push('в «' + где + '» уехало внутреннее имя места: ' + значение);
          }
        });
      }
      обход(значение, где);
    });
  })(вид, '');

  проверить(беды.length === 0, откуда + ': в виде нет внутренностей сервера' +
    (беды.length ? ' — ' + беды.join('; ') : ''));
}

