/** Свой генератор случайных чисел: с ним прогон повторяется слово в слово. */
function поставитьЗерно(семя) {
  let s = семя >>> 0;
  Math.random = function () {
    s = (Math.imul(s, 1664525) + 1013904223) >>> 0;
    return s / 4294967296;
  };
}

