/** Новый стол: белые — «человек», чёрные — «бот». */
function накрытьСтол(Игра, вариант) {
  return Игра.раздать(БЕЛЫЕ_МЕСТО, {
    игроки: [БЕЛЫЕ_МЕСТО, ЧЁРНЫЕ_МЕСТО],
    вариантНард: вариант
  });
}

/** Доска глазами игрока: живая партия правил, собранная из снимка вида. */
function доскаИзВида(вид) {
  return Правила.партияИзКартинки(вид.доска);
}

/** Отпечаток позиции и кубиков — по нему видно, что отказ ничего не тронул. */
function отпечатокСтола(вид) {
  return Правила.отпечатокПозиции(доскаИзВида(вид)) + ' | ' +
         JSON.stringify(вид.бросок) + ' | ' + JSON.stringify(вид.кубикиОсталось);
}

/** Перемещения в том виде, в каком их шлёт браузер: только откуда-куда-кубик. */
function шагиДляОтправки(ход) {
  return ход.шаги.map(function (ш) {
    return { откуда: ш.откуда, куда: ш.куда, кубик: ш.кубик };
  });
}

/** Случайный законный ход в этой позиции или null, если ходить нечем. */
function случайныйЗаконныйХод(доска) {
  const ходы = Правила.возможныеХоды(доска);
  if (!ходы.length) return null;
  return ходы[Math.floor(Math.random() * ходы.length)];
}

/** Законен ли такой ход сейчас — спрашиваем правила по КОПИИ доски. */
function ходЗаконен(доска, шаги) {
  return Правила.сделатьХод(Правила.копияПартии(доска), { шаги: шаги }) !== null;
}

/** Похоже ли значение на честный бросок игральных костей: непустой массив 1…6. */
function похожеНаБросок(бросок) {
  return Array.isArray(бросок) && бросок.length > 0 &&
    бросок.every(function (к) { return Number.isInteger(к) && к >= 1 && к <= 6; });
}

