/** Комната на двоих: A создаёт, B входит — партия раздаётся сама. */
function столВдвоём(игра) {
  const создана = комнаты.создатьКомнату(новыйАдрес(), { имя: 'Аня', телеграм: 1001, игра: игра });
  if (!создана.ок) throw new Error('комната не создалась: ' + создана.причина);
  const вход = комнаты.войтиВКомнату(создана.код, { имя: 'Боря', телеграм: 1002 });
  if (!вход.ок) throw new Error('второй не вошёл: ' + вход.причина);
  const A = комнаты.найтиИгрока(создана.код, создана.пропуск);
  const B = комнаты.найтиИгрока(создана.код, вход.пропуск);
  if (A.комната.этап === 'ожидание') комнаты.сделатьХод(A.комната, A.ктоЯ, { действие: 'начать' });
  return { комната: A.комната, A: A.ктоЯ, B: B.ктоЯ };
}

/** Компания на троих из людей: A хозяин, B и C входят, A жмёт «Начать». */
function компанияНаТроих() {
  const создана = комнаты.создатьКомнату(новыйАдрес(), { имя: 'Аня', телеграм: 2001, мест: 3 });
  if (!создана.ок) throw new Error('комната не создалась: ' + создана.причина);
  const входB = комнаты.войтиВКомнату(создана.код, { имя: 'Боря', телеграм: 2002 });
  const входC = комнаты.войтиВКомнату(создана.код, { имя: 'Вера', телеграм: 2003 });
  const A = комнаты.найтиИгрока(создана.код, создана.пропуск);
  const B = комнаты.найтиИгрока(создана.код, входB.пропуск);
  const C = комнаты.найтиИгрока(создана.код, входC.пропуск);
  const начали = комнаты.сделатьХод(A.комната, A.ктоЯ, { действие: 'начать' });
  if (!начали.принято) throw new Error('партия не началась: ' + начали.причина);
  return {
    комната: A.комната, A: A.ктоЯ, B: B.ктоЯ, C: C.ктоЯ, код: создана.код,
    // Пропуска нужны случаям с возвращением за стол (найтиИгрока → вернутьЗаСтол).
    пропуски: { A: создана.пропуск, B: входB.пропуск, C: входC.пропуск }
  };
}

/** Один человек и боты на остальных местах: мест — сколько всего за столом. */
function человекИБоты(мест) {
  const создана = комнаты.создатьКомнату(новыйАдрес(), { имя: 'Аня', телеграм: 3001, мест: мест });
  if (!создана.ок) throw new Error('комната не создалась: ' + создана.причина);
  const A = комнаты.найтиИгрока(создана.код, создана.пропуск);
  for (let i = 1; i < мест; i++) {
    const посадили = комнаты.сделатьХод(A.комната, A.ктоЯ, { действие: 'бот' });
    if (!посадили.принято) throw new Error('бот не сел: ' + посадили.причина);
  }
  if (A.комната.этап === 'ожидание') {
    const начали = комнаты.сделатьХод(A.комната, A.ктоЯ, { действие: 'начать' });
    if (!начали.принято) throw new Error('партия не началась: ' + начали.причина);
  }
  return { комната: A.комната, A: A.ктоЯ };
}

/** Ждать, пока условие не станет верным, но не дольше срока. Ответ — дождались ли. */
function ждать(условие, срокМс) {
  return new Promise(function (готово) {
    const начало = Date.now();
    (function шаг() {
      if (условие()) return готово(true);
      if (Date.now() - начало > срокМс) return готово(false);
      setTimeout(шаг, 10);
    })();
  });
}

/**
 * Ходить за ЛЮДЕЙ, пока очередь не дойдёт до «кто». Сам «кто» не ходит.
 * На боте останавливаемся: за бота ходит сервер, не проверка.
 */
function дуракДоОчереди(комната, кто) {
  for (let шаг = 0; шаг < 60; шаг++) {
    const ходит = партии.чейХод(комната.партия);
    if (ходит === кто) return true;
    const игрок = ходит ? комната.игроки[ходит] : null;
    if (!игрок || игрок.этоБот) return false;
    if (!ходДурака(комната, ходит)) return false;
  }
  return false;
}

/**
 * Любой законный ход дурака за того, чья очередь: заход любой картой,
 * «беру» или «бито». Правила сами скажут, что подошло.
 */
function ходДурака(комната, кто) {
  const рука = комната.партия.руки[кто] || [];
  const попытки = [];
  for (let i = 0; i < рука.length; i++) попытки.push({ действие: 'ходить', карта: i });
  попытки.push({ действие: 'беру' }, { действие: 'бито' });
  for (const намерение of попытки) {
    if (комнаты.сделатьХод(комната, кто, намерение).принято) return true;
  }
  return false;
}

/** Ходить за людей по очереди, пока этот игрок не сделает свой первый ход. */
function дуракДоХодаИгрока(комната, кто) {
  const люди = Object.keys(комната.игроки);
  for (let шаг = 0; шаг < 60; шаг++) {
    const ходит = партии.чейХод(комната.партия);
    if (!ходит || люди.indexOf(ходит) === -1) return false;
    const сделал = ходДурака(комната, ходит);
    if (!сделал) return false;
    if (ходит === кто) return true;
  }
  return false;
}

/** Первый законный ход шашек за того, чья очередь. */
function ходШашек(комната) {
  const ходит = реестр.игра('шашки').чейХод(комната.партия);
  const ход = ПравилаШашек.возможныеХоды(комната.партия.доска)[0];
  if (!ход) return null;
  const ответ = комнаты.сделатьХод(комната, ходит, { действие: 'ход', откуда: ход.откуда, куда: ход.куда });
  return ответ.принято ? ходит : null;
}

function одинаковыеСписки(а, б) {
  return Array.isArray(а) && Array.isArray(б) && а.length === б.length &&
    а.every(function (x, i) { return x === б[i]; });
}

function найтиВЗастолье(застолье, номер) {
  return (застолье || []).find(function (строка) { return строка.номер === номер; }) || null;
}

