async function значенияКубиков(страница) {
  return страница.evaluate(function () {
    const узлы = document.querySelectorAll('#кубики .кубик');
    return Array.prototype.map.call(узлы, function (у) { return Number(у.dataset.очки); });
  });
}

/**
 * Дожидается, пока кубики устоятся (мелькание — класс «кубик--катится» —
 * закончилось), и только тогда читает их значения. Простой sleep тут
 * ненадёжен: ВРЕМЯ_БРОСКА у экрана 620мс, и чтение на 500мс попадает
 * прямо в мелькание — читаются случайные промежуточные цифры.
 */
/**
 * Ждёт «окончательные» кубики двумя фазами:
 *   1) активно ловим момент, когда на столе появился класс «кубик--катится»
 *      (подтверждение, что НОВАЯ прокрутка правда началась — если не
 *      делать так, можно перепутать со старыми, уже устоявшимися кубиками
 *      от предыдущего показа: было замечено в ломающем прогоне, где
 *      испорченный клиент сам катит кубики раньше времени);
 *   2) ждём, пока этот класс снова исчезнет — тогда и читаем очки.
 * Если мелькания не случилось вовсе (фаза 1 ничего не поймала за отпущенное
 * время) — просто читаем то, что есть, вторым циклом с тем же таймаутом.
 */
async function читатьКубикиЕслиУстоялись(страница) {
  return страница.evaluate(function () {
    const узлы = document.querySelectorAll('#кубики .кубик');
    if (!узлы.length) return null;
    const катятся = Array.prototype.some.call(узлы, function (у) { return у.classList.contains('кубик--катится'); });
    if (катятся) return null;
    return Array.prototype.map.call(узлы, function (у) { return Number(у.dataset.очки); });
  });
}

async function дождатьсяКубиков(страница, таймаутМс) {
  таймаутМс = таймаутМс || 2000;
  /* Фаза 1 (окно шире — в headless-браузере первый тик анимации иногда
     откладывается заметно дольше 500мс): активно ловим момент, когда
     класс «кубик--катится» точно появился — подтверждение, что новая
     прокрутка началась, а мы не подсмотрели старые, ещё не смытые
     кубики от предыдущего показа. */
  const конецФазы1 = Date.now() + Math.min(900, таймаутМс);
  while (Date.now() < конецФазы1) {
    const катятся = await страница.evaluate(function () {
      return !!document.querySelector('#кубики .кубик--катится');
    });
    if (катятся) break;
    await спать(25);
  }
  /* Фаза 2: «устоялось» — только если ДВА последовательных снимка
     подряд (с паузой между ними) совпали. Одиночное совпадение не
     считаем: можно поймать значение ровно в момент между двумя тиками
     мелькания, ещё до того, как класс «кубик--катится» реально снят. */
  const конец = Date.now() + таймаутМс;
  let последние = [];
  while (Date.now() < конец) {
    const первое = await читатьКубикиЕслиУстоялись(страница);
    if (первое) {
      await спать(80);
      const второе = await читатьКубикиЕслиУстоялись(страница);
      if (второе && второе.slice().sort().join(',') === первое.slice().sort().join(',')) return второе;
      последние = второе || первое;
      continue;
    }
    последние = await значенияКубиков(страница);
    await спать(60);
  }
  return последние;
}

