/* =====================================================================
   ПРОВЕРКА: НАРДЫ — СЕТЕВОЙ ВИД (js/нарды-экран.js, часть 9б).

   Что тут проверяется — в двух словах: экран нард не бросает кубики
   сам и не решает исход партии сам, когда играет «по сети» — он только
   ПРОСИТ сервер и ПОКАЗЫВАЕТ то, что сервер прислал («вид»). Настоящего
   сервера тут нет — вместо него мы подсовываем экрану свой обработчик
   писем (window.НардыЭкран.включитьСеть) и сами шлём ему «виды» стола
   через window.НардыЭкран.показатьСетевойВид(вид), как будто сервер
   ответил. Дальше смотрим на экран и в письма, которые экран пытался
   отправить «на сервер».

   Один настоящий Chromium (playwright), страница уже раздаётся на
   http://127.0.0.1:8080/нарды.html — свой сервер тут не поднимаем.

   Обычный прогон:   node tests/нарды-сетевой-вид.js
   Ломающий прогон:   node tests/нарды-сетевой-вид.js --сломать
     — портит КОПИЮ js/нарды-экран.js во временной папке (сам файл
     проекта не трогаем НИКОГДА) и подсовывает её странице вместо
     настоящего файла. Ожидаем, что покраснеют пункты про бросок
     кубиков (2) и про текст сдачи (8).
   ===================================================================== */

