/** Карта «имя шашки → место» из снимка партии (картинкаПартии). Тот же вид, что и на экране. */
function картаИзСнимка(снимок) {
  const карта = {};
  for (let п = 1; п <= 24; п += 1) {
    (снимок.пункты[п] || []).forEach(function (имя) { карта[имя] = 'п' + п; });
  }
  (снимок.бар.белые || []).forEach(function (имя) { карта[имя] = 'бар-белые'; });
  (снимок.бар.чёрные || []).forEach(function (имя) { карта[имя] = 'бар-чёрные'; });
  (снимок.вне.белые || []).forEach(function (имя) { карта[имя] = 'вне-белые'; });
  (снимок.вне.чёрные || []).forEach(function (имя) { карта[имя] = 'вне-чёрные'; });
  return карта;
}

function картыРавны(а, б) {
  const ключиА = Object.keys(а).sort();
  const ключиБ = Object.keys(б).sort();
  if (ключиА.length !== ключиБ.length) return false;
  for (const к of ключиА) { if (а[к] !== б[к]) return false; }
  return true;
}

/** Жадно доигрывает ход партии до конца тем же правилами, что и человек: шаг за шагом. */
function доигратьХодДоКонца(партия) {
  const шаги = [];
  let охрана = 0;
  while (!Правила.ходЗакончен(партия) && охрана < 8) {
    охрана += 1;
    const варианты = Правила.возможныеШаги(партия);
    if (!варианты.length) break;
    const шаг = Правила.сделатьШаг(партия, варианты[0]);
    if (!шаг) break;
    шаги.push({ откуда: шаг.откуда, куда: шаг.куда, кубик: шаг.кубик });
  }
  return шаги;
}

/** Подбирает для чёрных бросок, при котором на текущей доске правда есть ход — иначе получим не «ход», а «пропуск». */
function найтиИгровойБросок(партия, цвет) {
  const кандидаты = [[4, 1], [3, 2], [5, 4], [6, 3], [2, 1], [5, 2], [6, 1], [4, 3], [6, 2], [5, 3], [6, 4], [6, 5], [3, 1]];
  for (const пара of кандидаты) {
    const копия = Правила.копияПартии(партия);
    if (Правила.чейХод(копия) !== цвет) return null;
    Правила.бросить(копия, пара);
    if (Правила.возможныеШаги(копия).length > 0) return пара;
  }
  return null;
}

