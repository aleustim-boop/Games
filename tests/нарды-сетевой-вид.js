/** Клик по месту доски (номер пункта, 'бар' или 'вне') — тем же кодом, что слушает доска.addEventListener. */
async function кликПоМесту(страница, место, цвет) {
  await страница.evaluate(function (аргументы) {
    const место = аргументы.место;
    const цвет = аргументы.цвет;
    let эл = null;
    if (место === 'бар') эл = document.querySelector('.бар__половина[data-бар="' + цвет + '"]');
    else if (место === 'вне') эл = document.querySelector('.полка[data-полка="' + цвет + '"]');
    else эл = document.querySelector('.пункт[data-пункт="' + место + '"]');
    if (эл) эл.dispatchEvent(new MouseEvent('click', { bubbles: true }));
  }, { место: String(место), цвет: цвет });
}

/**
 * Доигрывает ход тапами по подсветке экрана (шашка--можно-взять / пункт--можно) —
 * не гадаем заранее, что выпадет: смотрим, что подсветил сам экран, и жмём туда.
 * Возвращает true, когда кнопка «Подтвердить» стала доступна (ход дошёл до конца).
 */
async function довестиХодДоГотовности(страница, максПопыток) {
  максПопыток = максПопыток || 20;
  for (let i = 0; i < максПопыток; i += 1) {
    const состояние = await страница.evaluate(function () {
      const кнопка = document.getElementById('кнопка-закончить-ход');
      return {
        готово: !!кнопка && !кнопка.classList.contains('скрыт'),
        естьШашка: !!document.querySelector('.шашка--можно-взять')
      };
    });
    if (состояние.готово) return true;
    if (!состояние.естьШашка) return false;
    await страница.evaluate(function () {
      const шашка = document.querySelector('.шашка--можно-взять');
      шашка.dispatchEvent(new MouseEvent('click', { bubbles: true }));
    });
    await спать(180);
    const естьЦель = await страница.evaluate(function () {
      const цель = document.querySelector('.пункт--можно');
      if (!цель) return false;
      цель.dispatchEvent(new MouseEvent('click', { bubbles: true }));
      return true;
    });
    if (!естьЦель) return false;
    await спать(300);
  }
  return false;
}

async function картаНаЭкране(страница) {
  return страница.evaluate(function () {
    const карта = {};
    document.querySelectorAll('[data-шашка]').forEach(function (эл) {
      const родитель = эл.parentElement;
      let место = '?';
      if (родитель && родитель.dataset && родитель.dataset.пункт) место = 'п' + родитель.dataset.пункт;
      else if (родитель && родитель.dataset && родитель.dataset.бар) место = 'бар-' + родитель.dataset.бар;
      else if (родитель && родитель.dataset && родитель.dataset.полка) место = 'вне-' + родитель.dataset.полка;
      карта[эл.dataset.шашка] = место;
    });
    return карта;
  });
}

async function дождатьсяКартыРавной(страница, ожидаемая, таймаутМс) {
  const конец = Date.now() + таймаутМс;
  let последняя = null;
  while (Date.now() < конец) {
    последняя = await картаНаЭкране(страница);
    if (картыРавны(последняя, ожидаемая)) return { совпало: true, последняя: последняя };
    await спать(150);
  }
  return { совпало: false, последняя: последняя };
}

async function ждатьРост(получитьДлину, былоДлины, таймаутМс) {
  const конец = Date.now() + таймаутМс;
  while (Date.now() < конец) {
    const сейчас = await получитьДлину();
    if (сейчас > былоДлины) return true;
    await спать(120);
  }
  return false;
}

