let всегоПроверок = 0;
let всегоПровалов = 0;

/** Одна проверка: условие + понятный текст. Не бросает исключение — копит провалы. */
function проверить(условие, текст) {
  всегоПроверок += 1;
  if (условие) {
    console.log('  ок     — ' + текст);
  } else {
    всегоПровалов += 1;
    console.log('  ПРОВАЛ — ' + текст);
  }
  return !!условие;
}

function спать(мс) {
  return new Promise(function (готово) { setTimeout(готово, мс); });
}

/* ---------------------------------------------------------------------
   ЛОМАЮЩАЯ КОПИЯ. Портит ДВА места в КОПИИ файла (не в файле проекта):
     1) «Бросить» по сети сам катит кубики и ничего не шлёт на сервер.
     2) Текст итога никогда не узнаёт «сдачу» — сравнение всегда ложно.
   Если хоть одна из замен не нашла своё место — это уже не «ломающий
   прогон», а тишина; выходим кодом 2, чтобы это не выглядело зелёным.
   ------------------------------------------------------------------- */
function создатьСломаннуюКопию() {
  const исходный = path.join(КОРЕНЬ, 'js', 'нарды-экран.js');
  let текст = fs.readFileSync(исходный, 'utf8');
  let замен = 0;

  const было1 = "if (режим === 'сеть') { попроситьБросок(); return; }";
  const стало1 = "if (режим === 'сеть') { /* СЛОМАНО ТЕСТОМ: рисуем сами, серверу не пишем */ }";
  if (текст.indexOf(было1) !== -1) { текст = текст.split(было1).join(стало1); замен += 1; }

  const было2 = "if (итог.видПобеды === 'сдача') {";
  const стало2 = "if (итог.видПобеды === 'СЛОМАНО-ТЕСТОМ') {";
  if (текст.indexOf(было2) !== -1) { текст = текст.split(было2).join(стало2); замен += 1; }

  if (замен < 2) {
    console.error('Ломающий прогон: не нашёл место для порчи в js/нарды-экран.js (замен: ' + замен +
      ' из 2) — код игры мог измениться, проверку надо обновить. Портить нечего, это провал.');
    process.exit(2);
  }

  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'нарды-сломанный-'));
  const копия = path.join(папка, 'нарды-экран.js');
  fs.writeFileSync(копия, текст, 'utf8');
  console.log('Ломающая копия: ' + копия + ' (замен: ' + замен + ')');
  return копия;
}

