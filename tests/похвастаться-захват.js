'use strict';

/* Проверка: «Похвастаться» знает игру «захват» (этап Б10).
   В ТЗ (раздел 8.7) готового текста для чата нет, слова «в захвате» названы
   в штаб/игры/первая-игра/этапы.md (Б8, Б10) — их и сверяем оттуда.
   Файл общее/js/похвастаться.js браузерный, поэтому запускаем его в песочнице vm
   с поддельной страницей; слова без поля «слова» в описании собирает сам клиент.

   Запуск:  node tests/похвастаться-захват.js
   Ломающий запуск:  node tests/похвастаться-захват.js --сломать
   (копия файла во временной папке без записи «захват» — обязана покраснеть) */

const fs = require('fs');
const os = require('os');
const vm = require('vm');
const path = require('path');

const КОРЕНЬ = path.resolve(__dirname, '..');
const ПУТЬ_ФАЙЛА = path.join(КОРЕНЬ, 'общее', 'js', 'похвастаться.js');
const ПУТЬ_ЭТАПОВ = path.join(КОРЕНЬ, 'штаб', 'игры', 'первая-игра', 'этапы.md');
const ломаем = process.argv.includes('--сломать');

let всего = 0;
let провалов = 0;
function проверить(что, правда) {
  всего++;
  if (!правда) провалов++;
  console.log((правда ? '  ок   ' : '  БЕДА ') + что);
}

/** Поддельная страница: не в Telegram, значит слова уходят в буфер обмена. */
function собратьОкно() {
  const буфер = { текст: null };
  const окно = {
    location: { search: '', hash: '', protocol: 'https:', href: 'https://пример/Games/',
                origin: 'https://пример', pathname: '/Games/', host: 'пример' },
    localStorage: { getItem: function () { return null; }, setItem: function () {}, removeItem: function () {} },
    navigator: { clipboard: { writeText: function (т) { буфер.текст = т; return Promise.resolve(); } } }
  };
  const окружение = {
    window: окно, document: { getElementById: function () { return null; } },
    console: console, fetch: function () { return Promise.reject(new Error('сети нет')); },
    setTimeout: setTimeout, clearTimeout: clearTimeout,
    URLSearchParams: URLSearchParams, AbortController: AbortController,
    Promise: Promise, JSON: JSON, Number: Number
  };
  окружение.globalThis = окружение;
  return { окно: окно, окружение: окружение, буфер: буфер };
}

/** Слова, которые клиент собрал для описания игры «захват». */
async function словаЗахвата(исходник, описание) {
  const { окно, окружение, буфер } = собратьОкно();
  vm.runInNewContext(исходник, окружение, { filename: 'похвастаться.js' });
  await окно.Сеть.похвастаться(Object.assign({ игра: 'захват', исход: 'победа' }, описание));
  return буфер.текст ? буфер.текст.split(' https://')[0] : '';
}

async function прогнать(исходник) {
  const этапы = fs.readFileSync(ПУТЬ_ЭТАПОВ, 'utf8');
  const вЧём = /слова «(в захвате)»/.exec(этапы);
  // Ноль найденного — провал: слова из плана штаба обязаны найтись.
  проверить('в этапах штаба найдены слова про захват', Boolean(вЧём));
  const слова = вЧём ? вЧём[1] : '';

  const противБота = await словаЗахвата(исходник, { соперники: 'боты', уровень: 'сложный', игроков: 2 });
  проверить('победа над ботом: «Победа ' + слова + ' над сложным ботом. Сыграем?»',
    Boolean(слова) && противБота === 'Победа ' + слова + ' над сложным ботом. Сыграем?');

  const ботВшестером = await словаЗахвата(исходник, { соперники: 'боты', уровень: 'лёгкий', игроков: 6 });
  проверить('подстановка стола: бот вшестером',
    Boolean(слова) && ботВшестером === 'Победа ' + слова + ' над лёгким ботом вшестером. Сыграем?');

  const сЛюдьми = await словаЗахвата(исходник, { соперники: 'люди', игроков: 4 });
  проверить('победа с друзьями вчетвером',
    Boolean(слова) && сЛюдьми === 'Победа ' + слова + ' вчетвером с друзьями. Сыграем?');

  const общие = await словаЗахвата(исходник, { исход: 'победа', соперники: 'боты', игроков: 2 });
  проверить('слова — не общие «Победа. Сыграем?»', общие !== 'Победа. Сыграем?');
}

(async function () {
  let исходник = fs.readFileSync(ПУТЬ_ФАЙЛА, 'utf8');
  if (ломаем) {
    // Портим только копию во временной папке: файл проекта не трогаем.
    const порченый = исходник.replace(/\s*'захват':\s*'в захвате',?/, '');
    if (порченый === исходник) {
      console.log('  БЕДА ломающая подмена ничего не нашла (запись «захват» не обнаружена)');
      console.log('Итого проверок: 1, провалов: 1');
      process.exit(1);
    }
    const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-похвастаться-'));
    const копия = path.join(папка, 'похвастаться.js');
    fs.writeFileSync(копия, порченый, 'utf8');
    исходник = fs.readFileSync(копия, 'utf8');
    console.log('Ломающий запуск: копия без записи «захват» — ' + копия);
  }
  try {
    await прогнать(исходник);
  } catch (сбой) {
    проверить('проверка не упала: ' + сбой.message, false);
  }
  console.log('Итого проверок: ' + всего + ', провалов: ' + провалов);
  process.exit(провалов > 0 ? 1 : 0);
})();
