function случайДверьЗакрыта() {
  console.log('\n1) Закрытая игра (катан) на боевом сервере — поля «досрочно» нет; открытые игры берём из server/комнаты.js');
  /* Список открытых игр читаем из самого server/комнаты.js (не второй копией):
     «закрыто, как на боевом сервере» проверяем на игре, которой в нём нет
     (катан). Ноль найденного — провал: список обязан прочитаться и содержать
     дурака, вид катана — быть непустым. */
  const строкаСписка = (fs.readFileSync(path.join(ПАПКА, 'server', 'комнаты.js'), 'utf8')
    .match(/const ИГРЫ_С_ДОСРОЧНЫМ_КОНЦОМ = new Set\(\[([^\]]*)\]\)/) || [])[1] || '';
  const открытые = (строкаСписка.match(/'([^']+)'/g) || []).map(function (с) { return с.slice(1, -1); });
  проверить(открытые.length > 0 && открытые.indexOf('дурак') !== -1,
            'список открытых игр прочитан из server/комнаты.js, дурак в нём открыт: ' + открытые.join(', '));
  проверить(открытые.indexOf('катан') === -1, 'катан в списке открытых игр не числится — он здесь «закрытая игра»');
  const закрытая = собратьСтол('катан', 4, 4, 700090);
  for (const кто of ключиЛюдей) {
    const в = вид(закрытая.комната, закрытая.места[кто]);
    проверить(Object.keys(в).length > 3 && !Object.prototype.hasOwnProperty.call(в, 'досрочно'),
              кто + ': в виде катана поля «досрочно» нет');
  }
  комнаты.удалитьКомнату(закрытая.код);
  const стол = собратьСтол('деберц', 4, 4, 700100);

  /* Рассказ о событии при закрытой двери — прежний. До этапа 3 событие
     было ровно рассказом игры (деберц.текстСобытия), а он об уходе молчит:
     пустая строка. Общий рассказ голосования не должен её подменять. */
  const деберц = require(path.join(ПАПКА, 'server', 'игры', 'деберц.js'));
  const к = стол.комната;
  const м = стол.места;
  к.игроки[м.C].ходовВПартии = 1;
  комнаты.выйти(к, м.C);
  проверить(к.событие && к.событие.что === 'ушёл-бот', 'C вышел — событие «ушёл-бот», партию доигрывает бот');
  for (const кто of ['A', 'B', 'D']) {
    const в = вид(к, м[кто]);
    const прежний = деберц.текстСобытия(к.событие, м[кто]);
    проверить(прежний === '' && в.событие === '',
              кто + ': рассказ об уходе прежний — пустой, как у деберца до этапа 3 (получено «' + в.событие + '»)');
  }
  /* Брошенная партия вчетвером (так её кладёт выйти в ветке «партия
     отменена»): здесь вчетвером до неё не дойти уходом — место берёт бот, —
     поэтому состояние ставим руками. Старая страница читает «ничью». */
  к.партия.завершена = true;
  к.партия.результат = null;
  к.партия.проигравшие = [];
  const вA = вид(к, м.A);
  проверить(вA.деберц.ничья === true && вA.деберц.прервана === true && вA.деберц.победители.length === 0,
            'брошенная партия деберца вчетвером — «ничья» (как видят старые страницы), прервана, победителей нет');
  комнаты.удалитьКомнату(стол.код);

  // Вдвоём брошенная по-настоящему: ушёл до своего первого хода — партия отменена.
  const двое = собратьСтол('деберц', 2, 2, 700150);
  комнаты.выйти(двое.комната, двое.места.A);
  проверить(двое.комната.партия.завершена === true && двое.комната.партия.результат == null,
            'вдвоём A ушёл до первого хода — партия брошена без итога');
  const вB = вид(двое.комната, двое.места.B);
  проверить(вB.деберц.ничья === true && вB.деберц.прервана === true, 'B видит «ничью» брошенной партии, прервана');
  проверить(вB.событие === '', 'B: рассказ об уходе прежний — пустой (получено «' + вB.событие + '»)');
  комнаты.удалитьКомнату(двое.код);
}

