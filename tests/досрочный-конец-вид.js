const ИМЕНА = ['Аня', 'Боря', 'Вера', 'Гриша'];
const ключиЛюдей = ['A', 'B', 'C', 'D'];
/** Все номера Telegram, выданные в проверке, — их не должно быть ни в одном ответе. */
const выданныеТелеграмы = [];
/** Все пропуска — тоже. */
const выданныеПропуски = [];

/**
 * Стол на «мест» мест: людей — сколько просили, остальные места — боты.
 * Ответ: { комната, код, места: {A: ключМеста, ...}, боты: [ключи] }.
 */
function собратьСтол(игра, мест, людей, телеграмС) {
  выданныеТелеграмы.push(телеграмС);
  const создана = комнаты.создатьКомнату(новыйАдрес(), { имя: ИМЕНА[0], телеграм: телеграмС, игра: игра, мест: мест });
  if (!создана.ок) throw new Error('комната не создалась: ' + создана.причина);
  выданныеПропуски.push(создана.пропуск);
  const хозяин = комнаты.найтиИгрока(создана.код, создана.пропуск);
  const места = { A: хозяин.ктоЯ };
  for (let i = 1; i < людей; i++) {
    выданныеТелеграмы.push(телеграмС + i);
    const вход = комнаты.войтиВКомнату(создана.код, { имя: ИМЕНА[i], телеграм: телеграмС + i });
    if (!вход.ок) throw new Error(ключиЛюдей[i] + ' не вошёл: ' + вход.причина);
    выданныеПропуски.push(вход.пропуск);
    места[ключиЛюдей[i]] = комнаты.найтиИгрока(создана.код, вход.пропуск).ктоЯ;
  }
  for (let i = людей; i < мест; i++) {
    const посадили = комнаты.сделатьХод(хозяин.комната, хозяин.ктоЯ, { действие: 'бот' });
    if (!посадили.принято) throw new Error('бот не сел: ' + посадили.причина);
  }
  if (хозяин.комната.этап === 'ожидание') {
    const начали = комнаты.сделатьХод(хозяин.комната, хозяин.ктоЯ, { действие: 'начать' });
    if (!начали.принято) throw new Error('партия не началась: ' + начали.причина);
  }
  const к = хозяин.комната;
  const люди = Object.keys(места).map(function (б) { return места[б]; });
  const боты = к.партия.игроки.filter(function (м) { return люди.indexOf(м) === -1; });
  return { комната: к, код: создана.код, места: места, боты: боты };
}

/** Вид игрока — так, как он уедет по сети (через JSON). */
function вид(комната, кто) {
  return JSON.parse(JSON.stringify(комнаты.показатьИгроку(комната, кто)));
}

function предложить(комната, кто) {
  return комнаты.сделатьХод(комната, кто, { действие: 'закончить-предложить' });
}

function голос(комната, кто, за) {
  return комнаты.сделатьХод(комната, кто, { действие: 'закончить-голос', за: за });
}

function подождать(мс) {
  return new Promise(function (готово) { setTimeout(готово, мс); });
}

function одинаковыеСписки(а, б) {
  return Array.isArray(а) && Array.isArray(б) && а.length === б.length &&
    а.every(function (x, i) { return x === б[i]; });
}

/** Все ключи и строковые значения ответа — для поиска утечек. */
function обойти(значение, ключи, строки) {
  if (Array.isArray(значение)) {
    for (const x of значение) обойти(x, ключи, строки);
  } else if (значение && typeof значение === 'object') {
    for (const к of Object.keys(значение)) {
      ключи.push(к);
      обойти(значение[к], ключи, строки);
    }
  } else if (typeof значение === 'string') {
    строки.push(значение);
  }
}

const НАЗВАНИЯ_МЕСТ = партии.МЕСТА.map(function (м) { return м.toLowerCase(); });

/** Нет ли в ответе внутренних названий мест (ключом или значением), номеров Telegram и пропусков. */
function утечкиВОтвете(ответ) {
  const ключи = [];
  const строки = [];
  обойти(ответ, ключи, строки);
  const найдено = [];
  for (const к of ключи) if (НАЗВАНИЯ_МЕСТ.indexOf(к.trim().toLowerCase()) !== -1) найдено.push('ключ «' + к + '»');
  for (const с of строки) if (НАЗВАНИЯ_МЕСТ.indexOf(с.trim().toLowerCase()) !== -1) найдено.push('значение «' + с + '»');
  const текст = JSON.stringify(ответ);
  for (const т of выданныеТелеграмы) if (текст.indexOf(String(т)) !== -1) найдено.push('номер Telegram ' + т);
  for (const п of выданныеПропуски) if (п && текст.indexOf(п) !== -1) найдено.push('пропуск');
  return найдено;
}

