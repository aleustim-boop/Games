async function главная() {
  местаПоломокНаМесте();
  проверить(typeof комнаты.открытьДосрочныйКонецДляПроверки === 'function' &&
            typeof партии.досрочноДляИгрока === 'function',
            'в модулях есть открытьДосрочныйКонецДляПроверки и досрочноДляИгрока');
  // Сначала — дверь такая, какой её видят игроки на боевом сервере (открыта у деберца, домино, дурака и монополии; список читается в первом случае). Потом проверка открывает нужные игры сама.
  const случаи = [случайДверьЗакрыта, function () {
    комнаты.открытьДосрочныйКонецДляПроверки('деберц');
    комнаты.открытьДосрочныйКонецДляПроверки('монополия');
    комнаты.открытьДосрочныйКонецДляПроверки('дурак');
  }, случайВдвоём, случайКлючиИУтечки, случайГолосующийИНет, случайДеберцПрервана,
  случайУходДаётСогласие, случайИтогНеКХодуУшедшего, случайНесвежийНомерУхода,
  случайВывелиЗаМолчаниеСогласие, случайУходСнимает, случайПредложившийУшёл,
  случайПаузаТолькоЕслиПошло, случайМонополия, случайМонополияСПобедителем, случайСобытияВсем];
  for (const случай of случаи) {
    try {
      await случай();
    } catch (ошибка) {
      провалов++;
      console.log('  ✗ ПРОВАЛ: сценарий упал — ' + (ошибка && ошибка.stack ? ошибка.stack : ошибка));
    }
  }

  проверить(проверок >= МИНИМУМ_ПРОВЕРОК,
            'прогон не пустой: проверок ' + проверок + ' (нужно не меньше ' + МИНИМУМ_ПРОВЕРОК + ')');
  console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);
  if (НОМЕР_ПОЛОМКИ !== null) {
    console.log(провалов > 0
      ? 'Ломающий запуск №' + НОМЕР_ПОЛОМКИ + ': проверка покраснела, как и должна'
      : 'Ломающий запуск №' + НОМЕР_ПОЛОМКИ + ': проверка НЕ покраснела — она ничего не ловит');
  }
  // Будильники ботов в удалённых комнатах программу держать не должны — выходим явно.
  process.exit(провалов > 0 ? 1 : 0);
}

