#!/usr/bin/env node
'use strict';

/* =====================================================================
   ВСЕ ПРОПАЛИ РАЗОМ — хвост от ревьюера к правилам В1–В4 (пропажа связи
   это поражение, уход до первого хода — отмена, «Сдаться» остаётся).

   Стол компанией держит до шести мест, в том числе парами (вчетвером).
   Уже проверено (tests/выход-сдача-сервер.js, п.15): если пропадают
   РАЗОМ все трое за столом-тройкой — партия отменяется без поражений.
   НЕ проверено: то же самое на столе НА ЧЕТВЕРО (и без пар, и парами),
   а также случай «пропали не все, а трое из четырёх — один остался».

   ЧТО ПРОВЕРЯЕМ:
     1) 4 человека без пар: все четверо после нескольких ходов пропадают
        РАЗОМ (молчание длиннее срокПропажиНасовсем) — общий обрыв связи,
        партия отменена: комната закрыта, никому не поставлена «сдался»,
        рейтинг не вызван вовсе (поражение «против никого» — недопустимо).
     2) 4 места парами: пропадают ТРОЕ из четырёх, один остаётся на связи —
        это НЕ общий обрыв (не все четверо), значит каждый пропавший —
        обычная сдача: комната живёт, пока жив последний человек, рейтинг
        пока не звонит. Повторная уборка ничего не задваивает. Когда
        пропадает и последний человек — только тогда комната закрывается
        и рейтинг вызывается РОВНО один раз (не дважды, не по разу
        на каждого пропавшего).
     3) 4 человека без пар: все уходят САМИ (кнопкой «Выйти», не молчанием)
        ДО своего первого хода — партия отменена (решение В3): без
        поражений и без рейтинга, даже если уходили не в один и тот же
        миг, а по очереди.

   КАК ПРОВЕРЯЕМ. Сервер отдельным процессом/портом не поднимаем: комнаты
   живут в памяти одного процесса, поэтому берём приём tests/выход-сдача-
   сервер.js — зовём server/комнаты.js напрямую (require), без HTTP и без
   порта. Так можно рукой состарить «последнийЗапрос» игрока и вызвать
   комнаты.прибратьсяСейчас(...) сразу, не ожидая настоящих 3 минут
   молчания. Рейтинг подменён счётчиком вызовов — на диск ничего не
   пишется, боевых данных проверка не касается совсем (ДАННЫЕ_ИГРЫ на
   всякий случай тоже указывает во временную папку).

   ЛОМАЮЩИЙ ЗАПУСК: node tests/все-пропали-разом.js --сломать
   Берёт временную КОПИЮ server/ и js/ (боевые файлы не трогает) и в
   копии server/комнаты.js отключает подсчёт «общего обрыва» (всеРазом
   всегда false) — ровно та поломка, от которой предостерегал штаб:
   «заставь писать поражение всем». На такой копии сценарий 1 обязан
   провалиться: все четверо получат «сдался», а рейтинг спишет всем
   поражение против никого. Строка для порчи не нашлась — значит код
   изменился, и проверка честно останавливается (exit 2), а не молчит.

   Запуск:
     node tests/все-пропали-разом.js             обычный прогон, всё зелёное
     node tests/все-пропали-разом.js --сломать   копия без «всеРазом» — обязана покраснеть
   Выход 0 — провалов нет, 1 — есть провал, 2 — ломать было нечего (код изменился).
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const СЛОМАТЬ = process.argv.includes('--сломать');

/** Строка проверки «общего обрыва» в server/комнаты.js — дословно, с учётом \r\n. */
function испортитьКопию(путьККомнатам) {
  const исходник = fs.readFileSync(путьККомнатам, 'utf8');
  const шаблон = /const\s+всеРазом\s*=\s*пропалиНасовсем\.length\s*>=\s*2\s*&&\s*\r?\n\s*пропалиНасовсем\.length\s*===\s*людиЗаСтолом\(комната\)\.length;/;
  if (!шаблон.test(исходник)) {
    console.log('  БЕДА ломать нечего: строка проверки «всеРазом» в server/комнаты.js не найдена — код изменился, поправьте tests/все-пропали-разом.js');
    process.exit(2);
  }
  const испорчено = исходник.replace(шаблон,
    'const всеРазом = false; /* ИСПОРЧЕНО ПРОВЕРКОЙ tests/все-пропали-разом.js --сломать: общий обрыв связи снова пишет поражение всем подряд */');
  fs.writeFileSync(путьККомнатам, испорчено, 'utf8');
}

/** Своя копия server/ и js/ во временной папке — боевой код и боевые данные не трогаем. */
function подготовитьСломаннуюКопию() {
  const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'все-пропали-разом-'));
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(врем, 'server'), { recursive: true });
  fs.cpSync(path.join(КОРЕНЬ, 'js'), path.join(врем, 'js'), { recursive: true });
  испортитьКопию(path.join(врем, 'server', 'комнаты.js'));
  return врем;
}

const ПАПКА = СЛОМАТЬ ? подготовитьСломаннуюКопию() : КОРЕНЬ;
if (СЛОМАТЬ) {
  console.log('Ломающий прогон: копия server/комнаты.js с отключённым «всеРазом» — ждём провала.');
  process.on('exit', function () {
    try { fs.rmSync(ПАПКА, { recursive: true, force: true }); } catch (сбой) { /* не страшно */ }
  });
}

// Подстраховка: если что-то всё же попробует писать на диск — не в боевые данные.
const ВРЕМЕННЫЕ_ДАННЫЕ = fs.mkdtempSync(path.join(os.tmpdir(), 'все-пропали-разом-данные-'));
process.env.ДАННЫЕ_ИГРЫ = ВРЕМЕННЫЕ_ДАННЫЕ;
process.env.GAMES_DATA = ВРЕМЕННЫЕ_ДАННЫЕ;
process.on('exit', function () {
  try { fs.rmSync(ВРЕМЕННЫЕ_ДАННЫЕ, { recursive: true, force: true }); } catch (сбой) { /* не страшно */ }
});

const комнаты = require(path.join(ПАПКА, 'server', 'комнаты.js'));
const партии = require(path.join(ПАПКА, 'server', 'партия-по-сети.js'));
const рейтинг = require(path.join(ПАПКА, 'server', 'рейтинг.js'));

console.log('Папка с сервером: ' + ПАПКА);

let проверок = 0;
let провалов = 0;
function проверить(условие, что) {
  проверок++;
  if (условие) {
    console.log('  ✓ ' + что);
  } else {
    провалов++;
    console.log('  ✗ ПРОВАЛ: ' + что);
  }
}

/* Рейтинг подменён счётчиком вызовов: комнаты зовут его через объект
   модуля, подмена достаёт — на диск ничего не пишется совсем. */
const вызовыРейтинга = [];
рейтинг.учестьПартию = function (игра, застолье, ключ) {
  вызовыРейтинга.push({ игра: игра, застолье: застолье, ключ: ключ });
  return {};
};

let номерАдреса = 0;
function новыйАдрес() {
  номерАдреса++;
  return '10.0.9.' + номерАдреса;
}

/** Стол на четверых: A хозяин и создатель, Б/В/Г входят, A жмёт «Начать». */
function компанияНаЧетверых(база, парами) {
  const создана = комнаты.создатьКомнату(новыйАдрес(), {
    имя: 'Игрок А', телеграм: база + 1, мест: 4, парами: парами === true, игра: 'дурак'
  });
  if (!создана.ок) throw new Error('стол на четверых не создался: ' + создана.причина);
  const входБ = комнаты.войтиВКомнату(создана.код, { имя: 'Игрок Б', телеграм: база + 2 });
  const входВ = комнаты.войтиВКомнату(создана.код, { имя: 'Игрок В', телеграм: база + 3 });
  const входГ = комнаты.войтиВКомнату(создана.код, { имя: 'Игрок Г', телеграм: база + 4 });
  if (!входБ.ок || !входВ.ок || !входГ.ок) throw new Error('не все четверо вошли за стол');
  const A = комнаты.найтиИгрока(создана.код, создана.пропуск);
  const Б = комнаты.найтиИгрока(создана.код, входБ.пропуск);
  const В = комнаты.найтиИгрока(создана.код, входВ.пропуск);
  const Г = комнаты.найтиИгрока(создана.код, входГ.пропуск);
  const начали = комнаты.сделатьХод(A.комната, A.ктоЯ, { действие: 'начать' });
  if (!начали.принято) throw new Error('партия вчетвером не началась: ' + начали.причина);
  return {
    комната: A.комната, код: создана.код,
    A: A.ктоЯ, Б: Б.ктоЯ, В: В.ктоЯ, Г: Г.ктоЯ,
    пропуски: { A: создана.пропуск, Б: входБ.пропуск, В: входВ.пропуск, Г: входГ.пропуск },
    номера: { A: база + 1, Б: база + 2, В: база + 3, Г: база + 4 }
  };
}

/** Любой законный ход дурака за того, чья очередь: заход, «беру» или «бито». */
function ходДурака(комната, кто) {
  const рука = комната.партия.руки[кто] || [];
  const попытки = [];
  for (let i = 0; i < рука.length; i++) попытки.push({ действие: 'ходить', карта: i });
  попытки.push({ действие: 'беру' }, { действие: 'бито' });
  for (const намерение of попытки) {
    if (комнаты.сделатьХод(комната, кто, намерение).принято) return true;
  }
  return false;
}

/** Ходить за людей по очереди, пока этот игрок не сделает свой первый ход. */
function дуракДоХодаИгрока(комната, кто) {
  const люди = Object.keys(комната.игроки);
  for (let шаг = 0; шаг < 80; шаг++) {
    const ходит = партии.чейХод(комната.партия);
    if (!ходит || люди.indexOf(ходит) === -1) return false;
    const сделал = ходДурака(комната, ходит);
    if (!сделал) return false;
    if (ходит === кто) return true;
  }
  return false;
}

function найтиВЗастолье(застолье, номер) {
  return (застолье || []).find(function (строка) { return строка.номер === номер; }) || null;
}

/* ------------------------------------------------------------------ */
console.log('\n1) Стол на четверых без пар: все четверо пропадают РАЗОМ после ходов — отмена без поражений');
{
  const с = компанияНаЧетверых(61000, false);
  проверить(
    дуракДоХодаИгрока(с.комната, с.A) && дуракДоХодаИгрока(с.комната, с.Б) &&
    дуракДоХодаИгрока(с.комната, с.В) && дуракДоХодаИгрока(с.комната, с.Г),
    'все четверо успели сходить хотя бы по разу'
  );
  const давно = Date.now() - комнаты.срокПропажиНасовсем(с.комната) - 1000;
  const все = [{ м: 'A', к: с.A }, { м: 'Б', к: с.Б }, { м: 'В', к: с.В }, { м: 'Г', к: с.Г }];
  все.forEach(function (уч) { с.комната.игроки[уч.к].последнийЗапрос = давно; });
  const рейтингДо = вызовыРейтинга.length;

  комнаты.прибратьсяСейчас(Date.now());

  проверить(комнаты.найтиИгрока(с.код, с.пропуски.A) === null,
    'комната закрыта — молчание всех четверых распознано как общий обрыв');
  проверить(вызовыРейтинга.length === рейтингДо,
    'рейтинг НЕ вызван — общий обрыв связи не считается сдачей (поражение «против никого» недопустимо)');
  все.forEach(function (уч) {
    проверить(с.комната.игроки[уч.к].сдался !== true, 'у ' + уч.м + ' нет пометки «сдался»');
  });
}

/* ------------------------------------------------------------------ */
console.log('\n2) Стол парами на четверых: пропадают ТРОЕ из четырёх, один остаётся — без двойной записи рейтинга');
{
  const с = компанияНаЧетверых(62000, true);
  проверить(
    дуракДоХодаИгрока(с.комната, с.A) && дуракДоХодаИгрока(с.комната, с.Б) &&
    дуракДоХодаИгрока(с.комната, с.В) && дуракДоХодаИгрока(с.комната, с.Г),
    'все четверо успели сходить хотя бы по разу (парами)'
  );
  const давно = Date.now() - комнаты.срокПропажиНасовсем(с.комната) - 1000;
  const трое = [{ м: 'Б', к: с.Б }, { м: 'В', к: с.В }, { м: 'Г', к: с.Г }];
  трое.forEach(function (уч) { с.комната.игроки[уч.к].последнийЗапрос = давно; });
  с.комната.игроки[с.A].последнийЗапрос = Date.now();   // A на связи, молчит только для вида — не пропал
  const рейтингДо = вызовыРейтинга.length;

  комнаты.прибратьсяСейчас(Date.now());

  проверить(комнаты.найтиИгрока(с.код, с.пропуски.A) !== null,
    'комната жива — трое из четырёх это НЕ общий обрыв (А остаётся)');
  трое.forEach(function (уч) {
    проверить(с.комната.игроки[уч.к].этоБот === true && с.комната.игроки[уч.к].ушёл === true,
      уч.м + ' стал ботом и помечен ушедшим');
    проверить(с.комната.игроки[уч.к].сдался === true,
      уч.м + ' помечен «сдался» — против него ещё играл живой человек (А)');
  });
  проверить(с.комната.игроки[с.A].этоБот !== true && с.комната.игроки[с.A].ушёл !== true,
    'A остался живым человеком за столом');
  проверить(вызовыРейтинга.length === рейтингДо,
    'рейтинг ещё НЕ вызван — партия у оставшегося А продолжается, записывать пока нечего');

  // Повторная уборка сразу следом не должна ничего задваивать.
  комнаты.прибратьсяСейчас(Date.now());
  проверить(вызовыРейтинга.length === рейтингДо, 'повторная уборка не вызывает рейтинг повторно');
  проверить(комнаты.найтиИгрока(с.код, с.пропуски.A) !== null, 'комната по-прежнему жива после повторной уборки');

  // Наконец пропадает и последний человек — только теперь партия закрывается.
  с.комната.игроки[с.A].последнийЗапрос = Date.now() - комнаты.срокПропажиНасовсем(с.комната) - 1000;
  комнаты.прибратьсяСейчас(Date.now());

  проверить(комнаты.найтиИгрока(с.код, с.пропуски.A) === null,
    'комната закрылась, когда пропал и последний человек');
  проверить(вызовыРейтинга.length === рейтингДо + 1,
    'рейтинг вызван РОВНО один раз на всю партию — без задвоения по числу пропавших');

  const вызов = вызовыРейтинга[вызовыРейтинга.length - 1];
  [
    { кто: 'A', номер: с.номера.A },
    { кто: 'Б', номер: с.номера.Б },
    { кто: 'В', номер: с.номера.В },
    { кто: 'Г', номер: с.номера.Г }
  ].forEach(function (уч) {
    const строка = вызов ? найтиВЗастолье(вызов.застолье, уч.номер) : null;
    проверить(строка !== null, уч.кто + ' есть в застолье для рейтинга');
    проверить(строка && строка.победил === false, уч.кто + ' не отмечен победителем — все в итоге ушли сами');
  });

  // Уборка после закрытия комнаты — тоже без задвоения.
  комнаты.прибратьсяСейчас(Date.now());
  проверить(вызовыРейтинга.length === рейтингДо + 1, 'уборка после закрытия комнаты рейтинг больше не трогает');
}

/* ------------------------------------------------------------------ */
console.log('\n3) Стол на четверых без пар: все уходят САМИ до своего первого хода — отмена, без записей');
{
  const с = компанияНаЧетверых(63000, false);
  const все = [{ м: 'A', к: с.A }, { м: 'Б', к: с.Б }, { м: 'В', к: с.В }, { м: 'Г', к: с.Г }];
  const никтоНеХодил = все.every(function (уч) {
    return (с.комната.игроки[уч.к].ходовВПартии || 0) === 0;
  });
  проверить(никтоНеХодил, 'у всех четверых ноль ходов — раздача только что прошла');

  const рейтингДо = вызовыРейтинга.length;
  все.forEach(function (уч) { комнаты.выйти(с.комната, уч.к); });

  проверить(комнаты.найтиИгрока(с.код, с.пропуски.A) === null,
    'комната закрыта — все ушли до своего первого хода');
  проверить(вызовыРейтинга.length === рейтингДо,
    'рейтинг НЕ вызван — партия отменена (В3: нечаянный вход не наказывается)');
  все.forEach(function (уч) {
    проверить(с.комната.игроки[уч.к].сдался !== true, 'у ' + уч.м + ' нет пометки «сдался»');
  });
}

