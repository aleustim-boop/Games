/* =====================================================================
   ДВЕРЬ ДОСРОЧНОГО КОНЦА: ОТКРЫТА ТОЛЬКО ДЕБЕРЦУ (решение штаба 30.09)

   Запуск:
       node tests/досрочный-конец-дверь.js
       node tests/досрочный-конец-дверь.js --сломать <папка> <номер>

   Что проверяем на свежезагруженном сервере — БЕЗ помощника
   открытьДосрочныйКонецДляПроверки (в этом весь смысл: так сервер стоит
   на боевом порту):
     а) деберц на троих: предложение «закончить» принимается, двое
        других говорят «за» — партия закончена по согласию;
     б) домино на троих: то же действие отвергнуто словами двери
        («В этой игре закончить партию по согласию пока нельзя»),
        голосования нет, партия идёт, голос тоже отвергнут;
     в) в виде игрока деберца поле «досрочно» есть и ключи его те же,
        что в договоре; в виде игрока домино поля «досрочно» нет вовсе.

   Сервер НЕ поднимаем: зовём модуль комнат напрямую. Рейтинг пишет
   во временную папку (GAMES_DATA).

   Ломающий запуск. «--сломать <папка> <номер>»: <папка> вне проекта;
   внутри неё заводится НОВАЯ пустая папка, туда копируются server/ и js/,
   в копию кладётся одна поломка, и все сценарии гоняются на копии:
     1 — дверь снова пустая                 → краснеет (а) и (в);
     2 — в дверь добавлено ещё и домино     → краснеет (б) и (в).
   Места поломок ищутся по точному тексту: не нашлось ровно одно —
   выход с кодом 2. Файлы проекта не трогаются никогда.

   Выход: 0 — провалов нет, 1 — есть провал, 2 — поломку не вставить.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');

/* Строка двери в server/комнаты.js — единственное место, где она живёт. */
const СТРОКА_ДВЕРИ = "const ИГРЫ_С_ДОСРОЧНЫМ_КОНЦОМ = new Set(['деберц']);";

/* Слова отказа закрытой двери, как их сервер говорил и раньше. */
const ОТКАЗ_ЗАКРЫТОЙ_ДВЕРИ = 'В этой игре закончить партию по согласию пока нельзя';

/* Ключи поля «досрочно» — договор, как в tests/досрочный-конец-вид.js. */
const КЛЮЧИ_ДОСРОЧНО = ['идёт', 'предложил', 'имя', 'нужно', 'за', 'против', 'голосуют',
                        'мойГолос', 'яГолосую', 'секунд', 'можноПредложить', 'почему'];

const ПОЛОМКИ = {
  1: { что: 'дверь снова пустая: деберц закрыт', было: СТРОКА_ДВЕРИ,
       стало: 'const ИГРЫ_С_ДОСРОЧНЫМ_КОНЦОМ = new Set();' },
  2: { что: 'в дверь добавлено домино', было: СТРОКА_ДВЕРИ,
       стало: "const ИГРЫ_С_ДОСРОЧНЫМ_КОНЦОМ = new Set(['деберц', 'домино']);" }
};

function какВФайле(текст, кусок) {
  return текст.indexOf('\r\n') !== -1 ? кусок.split('\n').join('\r\n') : кусок;
}

function сколькоРаз(текст, кусок) {
  return текст.split(какВФайле(текст, кусок)).length - 1;
}

/* ---------- Разбор доводов и подготовка копии ---------- */

const гдеСломать = process.argv.indexOf('--сломать');
let ПАПКА = КОРЕНЬ;
let НОМЕР_ПОЛОМКИ = null;

if (гдеСломать !== -1) {
  const папкаКопий = process.argv[гдеСломать + 1];
  НОМЕР_ПОЛОМКИ = Number(process.argv[гдеСломать + 2]);
  const поломка = ПОЛОМКИ[НОМЕР_ПОЛОМКИ];
  if (!папкаКопий || !поломка) {
    console.log('Нужно: --сломать <папка> <номер>, номера: ' + Object.keys(ПОЛОМКИ).join(', '));
    process.exit(2);
  }
  const родитель = path.resolve(папкаКопий);
  const относительно = path.relative(КОРЕНЬ, родитель);
  if (!относительно || (!относительно.startsWith('..') && !path.isAbsolute(относительно))) {
    console.log('Папка для поломки лежит внутри проекта — отказываюсь: ' + родитель);
    process.exit(2);
  }
  fs.mkdirSync(родитель, { recursive: true });
  ПАПКА = fs.mkdtempSync(path.join(родитель, 'копия-' + НОМЕР_ПОЛОМКИ + '-'));
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(ПАПКА, 'server'), {
    recursive: true,
    filter: function (откуда) {
      const имя = path.basename(откуда);
      return имя !== 'данные' && имя !== 'node_modules';
    }
  });
  fs.cpSync(path.join(КОРЕНЬ, 'js'), path.join(ПАПКА, 'js'), { recursive: true });

  const куда = path.join(ПАПКА, 'server', 'комнаты.js');
  let текст = fs.readFileSync(куда, 'utf8');
  const нашлось = сколькоРаз(текст, поломка.было);
  if (нашлось !== 1) {
    console.log('Поломку №' + НОМЕР_ПОЛОМКИ + ' не вставить: строка двери найдена ' + нашлось +
                ' раз вместо одного. Проверка устарела — чините её.');
    process.exit(2);
  }
  текст = текст.split(какВФайле(текст, поломка.было)).join(какВФайле(текст, поломка.стало));
  fs.writeFileSync(куда, текст);
  console.log('ЛОМАЮЩИЙ ЗАПУСК №' + НОМЕР_ПОЛОМКИ + ': ' + поломка.что);
}

console.log('Папка с сервером: ' + ПАПКА);

process.env.GAMES_DATA = fs.mkdtempSync(path.join(os.tmpdir(), 'досрочный-конец-дверь-данные-'));

const комнаты = require(path.join(ПАПКА, 'server', 'комнаты.js'));

let проверок = 0;
let провалов = 0;

function проверить(условие, что) {
  проверок++;
  if (условие) {
    console.log('  ✓ ' + что);
  } else {
    провалов++;
    console.log('  ✗ ПРОВАЛ: ' + что);
  }
}

let номерАдреса = 0;
function новыйАдрес() {
  номерАдреса++;
  return '10.8.0.' + номерАдреса;
}

const ИМЕНА = ['Аня', 'Боря', 'Вера'];
const КЛЮЧИ = ['A', 'B', 'C'];

/** Стол на троих людей: { комната, код, места: {A, B, C} }. */
function столНаТроих(игра, телеграмС) {
  const создана = комнаты.создатьКомнату(новыйАдрес(), { имя: ИМЕНА[0], телеграм: телеграмС, игра: игра, мест: 3 });
  if (!создана.ок) throw new Error('комната не создалась: ' + создана.причина);
  const хозяин = комнаты.найтиИгрока(создана.код, создана.пропуск);
  const места = { A: хозяин.ктоЯ };
  for (let i = 1; i < 3; i++) {
    const вход = комнаты.войтиВКомнату(создана.код, { имя: ИМЕНА[i], телеграм: телеграмС + i });
    if (!вход.ок) throw new Error(КЛЮЧИ[i] + ' не вошёл: ' + вход.причина);
    места[КЛЮЧИ[i]] = комнаты.найтиИгрока(создана.код, вход.пропуск).ктоЯ;
  }
  if (хозяин.комната.этап === 'ожидание') {
    const начали = комнаты.сделатьХод(хозяин.комната, хозяин.ктоЯ, { действие: 'начать' });
    if (!начали.принято) throw new Error('партия не началась: ' + начали.причина);
  }
  return { комната: хозяин.комната, код: создана.код, места: места };
}

function партияИдёт(комната) {
  return комната.этап === 'игра' && Boolean(комната.партия) && !комната.партия.завершена;
}

function вид(комната, кто) {
  return JSON.parse(JSON.stringify(комнаты.показатьИгроку(комната, кто)));
}

function предложить(комната, кто) {
  return комнаты.сделатьХод(комната, кто, { действие: 'закончить-предложить' });
}

function голос(комната, кто, за) {
  return комнаты.сделатьХод(комната, кто, { действие: 'закончить-голос', за: за });
}

/* ============================ Сценарии ============================ */

function случайА() {
  console.log('\nа) Деберц на троих, дверь без помощника: предложение доходит до конца');
  const стол = столНаТроих('деберц', 71001);
  const к = стол.комната;
  const м = стол.места;
  проверить(к.игра === 'деберц', 'в комнате игра называется «деберц»');
  проверить(партияИдёт(к) && к.партия.игроки.length === 3, 'партия на 3 места идёт');

  const о = предложить(к, м.A);
  проверить(о.принято === true, 'A предлагает закончить — принято' + (о.принято ? '' : ' (отказ: «' + о.причина + '»)'));
  проверить(Boolean(к.досрочно) && к.досрочно.за.has(м.A), 'голосование заведено, A сразу «за»');
  проверить(партияИдёт(к), 'одно «за» из трёх — партия идёт (порог 3)');
  голос(к, м.B, true);
  проверить(партияИдёт(к), 'два «за» из трёх — партия идёт');
  const конец = голос(к, м.C, true);
  проверить(конец.принято === true && конец.событие === 'закончена-по-согласию',
            'третье «за» — ответ «закончена по согласию»');
  проверить(к.этап === 'конец' && к.партия.завершена === true, 'партия закончена');
  проверить(к.партия.законченаПоСогласию === true, 'партия помечена «закончена по согласию»');
  комнаты.удалитьКомнату(стол.код);
}

function случайБ() {
  console.log('\nб) Домино на троих, дверь без помощника: закрыта');
  const стол = столНаТроих('домино', 72001);
  const к = стол.комната;
  const м = стол.места;
  проверить(к.игра === 'домино', 'в комнате игра называется «домино»');
  проверить(партияИдёт(к) && к.партия.игроки.length === 3, 'партия на 3 места идёт');

  const о = предложить(к, м.A);
  проверить(о.принято === false, 'предложение — отказ');
  проверить(о.причина === ОТКАЗ_ЗАКРЫТОЙ_ДВЕРИ, 'слова отказа — как у закрытой двери: «' + о.причина + '»');
  проверить(!к.досрочно, 'голосования нет');
  проверить(партияИдёт(к), 'партия идёт');
  const г = голос(к, м.B, true);
  проверить(г.принято === false && г.причина === ОТКАЗ_ЗАКРЫТОЙ_ДВЕРИ, 'голос — тот же отказ');
  проверить(партияИдёт(к) && !к.досрочно, 'после голоса партия идёт, голосования нет');
  комнаты.удалитьКомнату(стол.код);
}

function случайВ() {
  console.log('\nв) Вид игрока: у деберца поля голосования есть, у домино их нет');
  const дебер = столНаТроих('деберц', 73001);
  const вДебер = вид(дебер.комната, дебер.места.A);
  const ключи = Object.keys(вДебер.досрочно || {});
  проверить(Object.prototype.hasOwnProperty.call(вДебер, 'досрочно') && ключи.length > 0,
            'в виде деберца поле «досрочно» есть');
  проверить(JSON.stringify(ключи) === JSON.stringify(КЛЮЧИ_ДОСРОЧНО),
            'ключи поля — по договору: ' + ключи.join(', '));
  проверить(Boolean(вДебер.досрочно) && вДебер.досрочно.идёт === false && вДебер.досрочно.можноПредложить === true,
            'голосования нет, предложить можно');
  проверить(Boolean(вДебер.досрочно) && вДебер.досрочно.голосуют === 3 && вДебер.досрочно.нужно === 3,
            'голосуют 3, нужно 3');
  комнаты.удалитьКомнату(дебер.код);

  const домино = столНаТроих('домино', 73101);
  for (const кто of КЛЮЧИ) {
    const в = вид(домино.комната, домино.места[кто]);
    проверить(!Object.prototype.hasOwnProperty.call(в, 'досрочно'), 'в виде домино (' + кто + ') поля «досрочно» нет');
  }
  /* Ноль найденного — провал: убеждаемся, что вид домино вообще непустой. */
  проверить(Object.keys(вид(домино.комната, домино.места.A)).length > 3, 'вид домино непустой (проверка не смотрит в пустоту)');
  комнаты.удалитьКомнату(домино.код);
}

function местоПоломкиНаМесте() {
  console.log('\n0) Строка двери есть в server/комнаты.js ровно один раз');
  const текст = fs.readFileSync(path.join(КОРЕНЬ, 'server', 'комнаты.js'), 'utf8');
  const н = сколькоРаз(текст, СТРОКА_ДВЕРИ);
  проверить(н === 1, 'строка двери с одним деберцем найдена ' + н + ' раз (проект)');
}

if (НОМЕР_ПОЛОМКИ === null) местоПоломкиНаМесте();
for (const случай of [случайА, случайБ, случайВ]) {
  try {
    случай();
  } catch (ошибка) {
    провалов++;
    console.log('  ✗ ПРОВАЛ: сценарий упал — ' + (ошибка && ошибка.stack ? ошибка.stack : ошибка));
  }
}

console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);
if (НОМЕР_ПОЛОМКИ !== null) {
  console.log(провалов > 0
    ? 'Ломающий запуск №' + НОМЕР_ПОЛОМКИ + ': проверка покраснела, как и должна'
    : 'Ломающий запуск №' + НОМЕР_ПОЛОМКИ + ': проверка НЕ покраснела — она ничего не ловит');
}
process.exit(провалов > 0 ? 1 : 0);
