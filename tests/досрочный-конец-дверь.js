/** Строка застолья рейтинга по номеру Telegram. */
function строкаРейтинга(застолье, телеграм) {
  return застолье.find(function (с) { return с.номер === телеграм; }) || null;
}

/** «Завершить участие» за A и проверка, что он и правда выбыл по правилам монополии. */
function выбытьA(стол) {
  const к = стол.комната;
  const номерA = к.партия.игроки.indexOf(стол.места.A);
  const о = комнаты.сделатьХод(к, стол.места.A, { действие: 'сдаться' });
  проверить(о.принято === true && номерA >= 0 && к.партия.игра.players[номерA].out === true,
            'A выбыл по правилам монополии' + (о.принято ? '' : ' (отказ: «' + о.причина + '»)'));
}

