'use strict';

/* =====================================================================
   ВЫХОД ВДВОЁМ ПОСЛЕ ПЕРВОГО ХОДА — ТЕПЕРЬ СДАЧА (тексты в js/game.js).

   Что проверяет. Сервер (server/партия-по-сети.js, server/комнаты.js)
   считает уход или пропажу со связи вдвоём ПОСЛЕ своего первого хода
   сдачей: победа оставшемуся, рейтинг считается. До первого хода —
   партия всё ещё отменяется без победителя, как раньше. Эта проверка
   смотрит на js/game.js — правильно ли браузер рассказывает про это:

     1) подпись плашки выхода («Завершить партию» на общем листе «⋯»)
        в сетевой партии вдвоём честно предупреждает о поражении,
        а не зовёт «друг останется за столом один» (это было правдой
        до правила про сдачу — теперь нет: партия не «останется»,
        она сразу засчитается);
     2) на событие сервера 'пропал-сдача' (и рядом — 'ушёл-сдача')
        итог у оставшегося — честная победа: заголовок «Вы выиграли!»,
        партия.результат — обычное 'бот' (как при доигранной партии),
        а не 'друг-ушёл'/'связь-потеряна'. И «другНеДождался» ложно —
        нет ни «Друг не дождался», ни «Позвать на реванш уже некого»
        там, где реванша и не предлагали бы, но победа честная.

   Как проверяет. Поднимает НАСТОЯЩИЙ js/game.js в песочнице vm (документ
   и его узлы — из tests/поддельный-браузер.js: classList/textContent
   ведут себя как в браузере). Зовёт публичную дверь сети
   window.ИграПоСети.показатьВид(вид) — тот же путь, каким js/сеть.js
   отдаёт игре каждый новый ответ сервера, — с вручную собранным «вид»,
   какой прислал бы сервер при сдаче (те же поля, что «видДляИгрока»
   в server/партия-по-сети.js: завершена, итог, видСобытия, соперникУшёл).

   Запуск:
       node tests/выход-сдача-тексты.js                — обычный прогон
       node tests/выход-сдача-тексты.js --файл <путь>  — тот же набор
         проверок, но js/game.js берётся не с диска проекта, а из файла
         по указанному пути (для ломающего запуска: путь ведёт на
         испорченную КОПИЮ во временной папке, настоящий js/game.js
         эта проверка не трогает).
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { сделатьДокумент } = require('./поддельный-браузер');

const КОРЕНЬ = path.join(__dirname, '..');

function аргумент(имя) {
  const индекс = process.argv.indexOf(имя);
  return индекс !== -1 ? process.argv[индекс + 1] : null;
}

const путьGameJsИзАргумента = аргумент('--файл') || path.join(КОРЕНЬ, 'js', 'game.js');

/**
 * document.getElementById, который на незнакомый id не возвращает null,
 * а честную пустышку (рабочие classList/appendChild/querySelector), — так
 * же, как в tests/выход-дурак.js. game.js при запуске и при показе итога
 * трогает сотни id разметки стола (счёт, витрина, кнопки), заводить их
 * все тут ни к чему — важны только тексты и переменные верхнего уровня.
 */
function позволитьЛюбыеId(документ) {
  const оригинал = документ.getElementById;
  const пустышки = new Map();
  документ.getElementById = function (id) {
    const найден = оригинал(id);
    if (найден) return найден;
    if (пустышки.has(id)) return пустышки.get(id);
    const узел = документ.createElement('div');
    узел.id = id;
    пустышки.set(id, узел);
    return узел;
  };
}

/** Поднять js/game.js в песочнице vm. Возвращает документ и «спросить». */
function поднятьИгру(путьGameJs) {
  const документ = сделатьДокумент();
  позволитьЛюбыеId(документ);

  const окно = {
    document: документ,
    addEventListener: function () {},
    removeEventListener: function () {},
    matchMedia: function () { return { matches: false, addEventListener: function () {}, addListener: function () {} }; },
    localStorage: { getItem: function () { return null; }, setItem: function () {}, removeItem: function () {} },
    innerWidth: 390, innerHeight: 844,
    requestAnimationFrame: function (ф) { return setTimeout(ф, 0); },
    cancelAnimationFrame: function (id) { clearTimeout(id); },
    getComputedStyle: function () {
      return { fontSize: '16px', lineHeight: '19.2px', getPropertyValue: function () { return ''; } };
    }
    // window.AudioContext нарочно нет: получитьЗвуковойДвижок() тогда
    // молча вернёт null, и сигнал() ничего не делает — звук тут не важен.
  };

  const песочница = {
    window: окно,
    document: документ,
    localStorage: окно.localStorage,
    navigator: { userAgent: 'тест выход-сдача-тексты' },
    // Предупреждение про недостающий js/дурак-путь.js (лобби) — обычное
    // дело для песочницы без разметки лобби, тексту итога оно не мешает.
    console: { log: function () {}, info: function () {}, warn: function () {}, error: function () {} },
    setTimeout: setTimeout, clearTimeout: clearTimeout,
    setInterval: setInterval, clearInterval: clearInterval,
    Math: Math, Date: Date, JSON: JSON, Number: Number, String: String, Array: Array, Object: Object,
    Boolean: Boolean, RegExp: RegExp, Error: Error, isFinite: isFinite, isNaN: isNaN,
    parseInt: parseInt, parseFloat: parseFloat, Map: Map, Set: Set,
    requestAnimationFrame: окно.requestAnimationFrame,
    cancelAnimationFrame: окно.cancelAnimationFrame,
    getComputedStyle: окно.getComputedStyle
  };
  песочница.globalThis = песочница;
  vm.createContext(песочница);
  vm.runInContext(fs.readFileSync(путьGameJs, 'utf8'), песочница, { filename: путьGameJs + ' (выход-сдача-тексты)' });

  return {
    документ: документ,
    /** Прочитать выражение или вызвать функцию верхнего уровня game.js
     *  («партия», «режим», «другСдался» — «let», свойствами песочницы
     *  не становятся, читаются и пишутся только через vm.runInContext). */
    спросить: function (выражение) { return vm.runInContext(выражение, песочница); },
    /** Отдать серверный «вид» в игру той же дверью, что и js/сеть.js. */
    показатьВид: function (вид) {
      vm.runInContext('window.ИграПоСети.показатьВид(' + JSON.stringify(вид) + ')', песочница);
    }
  };
}

/* Минимальный честный «вид» партии вдвоём, какая идёт своим ходом:
   те же поля, что видДляИгрока кладёт в ответ (см. server/партия-по-сети.js).
   Дальше каждый сценарий берёт эту заготовку и меняет несколько полей. */
function видПартииВПроцессе(номерСобытия) {
  return {
    завершена: false, итог: null,
    соперникПришёл: true, соперникНаСвязи: true,
    мояРука: [{ масть: '♠', имя: '6', вес: 6 }, { масть: '♥', имя: '7', вес: 7 }],
    картУСоперника: 2,
    стол: [],
    козырь: '♠', козырнаяКарта: { масть: '♠', имя: '6', вес: 6 },
    вКолоде: 20, вОтбое: 0, подходов: 1,
    яХожу: true, яАтакую: true,
    берут: false, могуПодкинуть: false, могуПеревести: false, могуПодхватить: false,
    номерСобытия: номерСобытия
  };
}

/** Тот же стол, но партия сдачей завершена: победа нам (итог «победа»). */
function видСдачи(номерСобытия, видСобытия) {
  const вид = видПартииВПроцессе(номерСобытия);
  вид.завершена = true;
  вид.итог = 'победа';
  вид.видСобытия = видСобытия;
  вид.соперникУшёл = true;
  вид.соперникНаСвязи = false;
  return вид;
}

/* =======================================================================
   ВЕСЬ НАБОР ПРОВЕРОК ОДНИМ ПРОГОНОМ
   ======================================================================= */
function прогнать(путьGameJs) {
  const строки = [];
  let провалов = 0;

  function проверить(имя, условие, подробности) {
    if (условие) {
      строки.push('OK    ' + имя);
    } else {
      провалов++;
      строки.push('ПЛОХО ' + имя + (подробности ? ' — ' + подробности : ''));
    }
  }

  /* --- 1) Подпись плашки выхода вдвоём — честное предупреждение о поражении --- */
  let игра1 = null;
  try {
    игра1 = поднятьИгру(путьGameJs);
    проверить('1) js/game.js поднимается в песочнице', true);
  } catch (сбой) {
    проверить('1) js/game.js поднимается в песочнице', false, сбой.message);
  }
  if (игра1) {
    игра1.спросить("режим = 'сеть'; партия = { завершена: false };");
    const подписьВдвоём = игра1.спросить('подписьВыхода()');
    /* Точное совпадение, не только indexOf('поражение'): текст обязан
       оговаривать условие «если уже ходили» — иначе он врёт игроку,
       который выходит ДО своего первого хода (правило В3: тогда
       партия просто отменяется, поражения не будет). */
    проверить('1а) вдвоём: подпись выхода — честный текст с оговоркой «если уже ходили»',
      подписьВдвоём === 'Если вы уже ходили — партия засчитается как поражение, победа сопернику.',
      'получено: ' + JSON.stringify(подписьВдвоём));
    проверить('1б) вдвоём: старого текста «друг останется за столом один» больше нет',
      typeof подписьВдвоём === 'string' && подписьВдвоём.indexOf('останется за столом') === -1,
      'получено: ' + JSON.stringify(подписьВдвоём));

    // Компанию эта правка не должна была тронуть — сверяем ту же подпись,
    // что и раньше (штаб просил компанию не менять).
    игра1.спросить("партия = { завершена: false, застолом: [{}, {}, {}] };");
    const подписьКомпанией = игра1.спросить('подписьВыхода()');
    проверить('1в) компанией: подпись выхода не тронута («доиграет бот»)',
      подписьКомпанией === 'Вы выйдете из партии — ваши карты доиграет бот, остальные продолжат.',
      'получено: ' + JSON.stringify(подписьКомпанией));
  }

  /* --- 2) Событие 'пропал-сдача': честная победа, не «не дождался» --- */
  let игра2 = null;
  try {
    игра2 = поднятьИгру(путьGameJs);
    игра2.показатьВид(видПартииВПроцессе(1));    // партия идёт своим ходом
    игра2.показатьВид(видСдачи(2, 'пропал-сдача'));  // и вдруг сдача пропажей связи
    проверить('2) партия дошла до сдачи «пропал-сдача» без падений', true);
  } catch (сбой) {
    проверить('2) партия дошла до сдачи «пропал-сдача» без падений', false, сбой.stack || сбой.message);
  }
  if (игра2) {
    проверить('2а) итог у оставшегося — честная победа (партия.результат === «бот»)',
      игра2.спросить('партия.результат') === 'бот',
      'получено: ' + JSON.stringify(игра2.спросить('партия.результат')));
    проверить('2б) «пропал-сдача» — не отмена партии («связь-потеряна» тут неверно)',
      игра2.спросить('партия.результат') !== 'связь-потеряна' &&
      игра2.спросить('партия.результат') !== 'друг-ушёл');
    проверить('2в) другНеДождался ложно — это не «партия отменена молчанием», а победа',
      игра2.спросить('другНеДождался') === false,
      'получено: ' + JSON.stringify(игра2.спросить('другНеДождался')));
    проверить('2г) другСдался истинно — сервер прислал слово сдачи',
      игра2.спросить('другСдался') === true);
    const текстыИтога2 = игра2.спросить('текстыИтога()');
    проверить('2д) заголовок итога — «Вы выиграли!», не «Друг не дождался»',
      текстыИтога2 && текстыИтога2.заголовок === 'Вы выиграли!',
      'получено: ' + JSON.stringify(текстыИтога2));
    проверить('2е) пояснение честно называет причину («пропал» или «связ»), а не «он и есть дурак»',
      текстыИтога2 && typeof текстыИтога2.пояснение === 'string' &&
      текстыИтога2.пояснение.indexOf('остался с картами') === -1 &&
      (текстыИтога2.пояснение.indexOf('пропал') !== -1 || текстыИтога2.пояснение.indexOf('связ') !== -1),
      'получено: ' + JSON.stringify(текстыИтога2));
    const концовка2 = игра2.спросить('разобратьКонцовку(' + JSON.stringify(видСдачи(2, 'пропал-сдача')) + ')');
    проверить('2ж) подсказка не врёт «Позвать на реванш уже некого» (партия не отменена, а выиграна)',
      концовка2 && (!концовка2.подсказка || концовка2.подсказка.indexOf('уже некого') === -1),
      'получено: ' + JSON.stringify(концовка2));
  }

  /* --- 3) Событие 'ушёл-сдача' (соперник вышел сам, не пропал) — тоже честная победа --- */
  let игра3 = null;
  try {
    игра3 = поднятьИгру(путьGameJs);
    игра3.показатьВид(видПартииВПроцессе(1));
    игра3.показатьВид(видСдачи(2, 'ушёл-сдача'));
    проверить('3) партия дошла до сдачи «ушёл-сдача» без падений', true);
  } catch (сбой) {
    проверить('3) партия дошла до сдачи «ушёл-сдача» без падений', false, сбой.stack || сбой.message);
  }
  if (игра3) {
    проверить('3а) итог у оставшегося — честная победа (партия.результат === «бот»)',
      игра3.спросить('партия.результат') === 'бот');
    проверить('3б) другНеДождался ложно и здесь — уход по своей воле, не молчание',
      игра3.спросить('другНеДождался') === false);
    const текстыИтога3 = игра3.спросить('текстыИтога()');
    проверить('3в) заголовок итога — «Вы выиграли!»',
      текстыИтога3 && текстыИтога3.заголовок === 'Вы выиграли!',
      'получено: ' + JSON.stringify(текстыИтога3));
    проверить('3г) слова «ушёл-сдача» и «пропал-сдача» рассказывают по-разному (сдался сам ≠ пропал)',
      текстыИтога3 && typeof текстыИтога3.пояснение === 'string' &&
      текстыИтога3.пояснение.indexOf('пропал') === -1,
      'получено: ' + JSON.stringify(текстыИтога3));
  }

  return { строки: строки, провалов: провалов };
}

console.log('=== Выход вдвоём — сдача: тексты в игре (файл: ' + путьGameJsИзАргумента + ') ===\n');
const { строки, провалов } = прогнать(путьGameJsИзАргумента);
строки.forEach(function (с) { console.log(с); });
console.log('');
console.log('Итого проверок: ' + строки.length + ', провалов: ' + провалов);
process.exitCode = провалов ? 1 : 0;
