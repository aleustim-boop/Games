'use strict';

/* =====================================================================
   ЛЕНТА БОТА: письма игроку о событиях стола (этап 1 — чистый модуль).

   Что проверяем. server/лента.js — модуль, который ни к чему не
   подключён: он получает описание события («кто-то сел за стол»,
   «стол собрался», «партия началась», «зовут ещё раз») и решает, кому
   из сидящих отправить письмо, с каким текстом и когда. Настоящего
   Telegram здесь нет и сети тоже нет — вместо них подставлены
   поддельные функции (отправить/почемуНеЗвать/запретить/ещёЗаСтолом)
   и управляемые часы (сейчас/отложить), чтобы не ждать реальных секунд
   и часов ради проверки пределов.

   Чем эта лента опасна, если ошибиться. Она пишет людям ОТ ИМЕНИ БОТА
   без отдельного согласия на каждое письмо — точно так же, как зов
   знакомого. Обмани её — и человек, который свернул экран или попросил
   «не звать меня», получит письмо всё равно; или один шумный стол
   засыплет письмами весь час. Поэтому здесь проверяется и то, что
   письмо доходит РОВНО куда нужно, и то, что оно РОВНО НЕ доходит,
   куда не нужно.

   Запуск:
       node tests/лента-бота.js

   Ломающий прогон (проверка обязана покраснеть):
       node tests/лента-бота.js --сломать
   «--сломать» не трогает файл кода server/лента.js и не подменяет
   чтение журнала (письмаКому() всегда читает журнал честно) — вместо
   этого портятся зависимости, которые лента получает через
   подключить(): поддельноеЕщёЗаСтолом начинает лгать «да, все ещё за
   столом» всегда, а поддельноеУЭкрана — «нет, никто не у экрана»
   всегда. Лента реально работает с этими враньём как с правдой, и
   поэтому реально рассылает письма туда, куда не должна: призракам
   посадки (пп. 1, 2) и вернувшимся к экрану (п. 5). Каждая такая
   сверка «после отката/возврата писем нет» обязана провалиться.

   Выход 0 — провалов нет, 1 — есть.
   ===================================================================== */

const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const лента = require(path.join(КОРЕНЬ, 'server', 'лента.js'));

const ЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;
if (ЛОМАТЬ) {
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: зависимости ещёЗаСтолом/уЭкрана начинают лгать (всегда «за столом», ' +
              'всегда «не у экрана») — лента реально шлёт письма призракам и вернувшимся, ' +
              'проверка обязана покраснеть ***');
}

let проверок = 0;
const провалы = [];

function проверить(условие, что) {
  проверок++;
  if (!условие) {
    провалы.push(что);
    console.log('  ПРОВАЛ: ' + что);
  }
}

/* ---------------------------------------------------------------------
   Управляемые часы: сейчас() возвращает мок-время, отложить() не ждёт
   по-настоящему, а кладёт дело в очередь до вызова продвинутьВремя().
   --------------------------------------------------------------------- */
let текущееВремя = 1700000000000;               // произвольная стартовая точка
const очередьОтложенных = [];

function мокСейчас() { return текущееВремя; }

function мокОтложить(дело, мс) {
  очередьОтложенных.push({ времяЗапуска: текущееВремя + мс, дело: дело, выполнено: false });
}

/** Сдвинуть часы вперёд и выполнить все дела, чьё время подошло. */
function продвинутьВремя(мс) {
  текущееВремя += мс;
  for (const запись of очередьОтложенных) {
    if (!запись.выполнено && запись.времяЗапуска <= текущееВремя) {
      запись.выполнено = true;
      запись.дело();
    }
  }
}

/** Дать микрозадачам (then у Promise) выполниться — нужно после
 *  продвинутьВремя(), если внутри дела была отправка через Promise. */
function дождатьсяОбработки() {
  return new Promise(function (готово) { setImmediate(готово); });
}

/* ---------------------------------------------------------------------
   Поддельный мир вокруг ленты.
   --------------------------------------------------------------------- */
const журнал = [];                 // все «отправленные» письма: { chat_id, text, reply_markup }
const комуНеПишем = new Set();     // этим Telegram отвечает отказом 403
const запретыИзЗа403 = new Map();  // номер → причина, которую записал запретить()
const собственныеОтказы = new Map(); // номер → 'сам' | 'ботНеПишет' (для почемуНеЗвать)
const ушедшиеСоСтола = new Set();  // 'код:номер' — кому ещёЗаСтолом() отвечает «нет»
const вернулисьКЭкрану = new Set(); // 'код:номер' — кому уЭкрана() отвечает «да»

function поддельноеОтправить(тело) {
  журнал.push(тело);
  if (комуНеПишем.has(Number(тело.chat_id))) {
    return { ok: false, error_code: 403, description: 'Forbidden: bot was blocked by the user' };
  }
  return { ok: true };
}

function поддельноеПочемуНеЗвать(номер) {
  return собственныеОтказы.get(номер) || '';
}

function поддельноеЗапретить(номер, причина) {
  запретыИзЗа403.set(номер, причина);
}

/* Ломающий запуск портит САМУ ленту, а не то, как проверка читает журнал:
   обе зависимости о «где сейчас человек» начинают врать, будто все всё
   ещё за столом и никто не у экрана — то есть лента перестаёт видеть
   и призраков посадки, и вернувшихся к экрану, и шлёт письма туда,
   куда не должна. Каждая сверка «после отката/возврата писем нет»
   обязана на этом промахнуться. */
function поддельноеЕщёЗаСтолом(код, номер) {
  if (Number(номер) <= 0) return false;  // как настоящая комнаты.сидитЗаСтолом — без номера никого не найти
  if (ЛОМАТЬ) return true;
  return !ушедшиеСоСтола.has(код + ':' + номер);
}

function поддельноеУЭкрана(код, номер) {
  if (ЛОМАТЬ) return false;
  return вернулисьКЭкрану.has(код + ':' + номер);
}

/** Все письма, ушедшие этому человеку — честное чтение журнала, без
 *  подмены (её тут нарочно нет: ломающий запуск портит поведение самой
 *  ленты через зависимости выше, а не то, как проверка смотрит на журнал). */
function письмаКому(номер) {
  return журнал.filter(function (запись) { return Number(запись.chat_id) === номер; });
}

/* ---------------------------------------------------------------------
   Проверки
   --------------------------------------------------------------------- */

async function проверитьВсё() {
  лента.подключить({
    отправить: поддельноеОтправить,
    почемуНеЗвать: поддельноеПочемуНеЗвать,
    запретить: поддельноеЗапретить,
    ещёЗаСтолом: поддельноеЕщёЗаСтолом,
    уЭкрана: поддельноеУЭкрана,
    сейчас: мокСейчас,
    отложить: мокОтложить
  });

  // --- 1. Честное письмо: ровно одному нужному человеку
  console.log('1. Честное письмо: у экрана — ноль, сам вызвавший — ноль, без номера — ноль');
  лента.событие({
    что: '4', игра: 'дурак', код: 'K001', ктоИмя: 'Аня', ктоНомер: 201,
    кому: [
      { номер: 202, наЭкране: false },   // получит письмо
      { номер: 203, наЭкране: true },    // у экрана — письма не будет
      { номер: 201, наЭкране: false },   // сам вызвавший — письма не будет
      { номер: 0, наЭкране: false }      // без настоящего номера — письма не будет
    ]
  });
  проверить(письмаКому(202).length === 1, 'обычному адресату должно уйти ровно одно письмо');
  проверить(письмаКому(203).length === 0, 'тому, кто держит экран открытым, письмо не нужно');
  проверить(письмаКому(201).length === 0, 'сам вызвавший событие не должен получать о нём письмо');
  проверить(письмаКому(0).length === 0, 'без настоящего номера Telegram письма не бывает');

  // --- 2. Запрет «сам» и «ботНеПишет»
  console.log('2. Запрет «сам»/«ботНеПишет»');
  собственныеОтказы.set(204, 'сам');
  собственныеОтказы.set(205, 'ботНеПишет');
  лента.событие({
    что: '4', игра: 'дурак', код: 'K002', ктоИмя: 'Аня', ктоНомер: 201,
    кому: [{ номер: 204, наЭкране: false }, { номер: 205, наЭкране: false }]
  });
  проверить(письмаКому(204).length === 0, 'человек, попросивший «не звать меня», не должен получить письмо');
  проверить(письмаКому(205).length === 0, 'тому, кому бот не пишет (403), письма тоже не должно быть');

  // --- 3. Кнопка «Не звать меня» в каждом письме
  console.log('3. Кнопка «Не звать меня»');
  const первоеПисьмо = письмаКому(202)[0];
  if (!ЛОМАТЬ) {
    const кнопки = (первоеПисьмо && первоеПисьмо.reply_markup && первоеПисьмо.reply_markup.inline_keyboard) || [];
    const последняяСтрока = кнопки[кнопки.length - 1] || [];
    проверить(последняяСтрока[0] && последняяСтрока[0].callback_data === 'не-звать',
      'в каждом письме ленты обязана быть кнопка «Не звать меня» с callback_data «не-звать»');
    проверить(кнопки.length === 1, 'без ссылки за стол в письме должна быть только одна кнопка');
  }

  // --- 4. Со ссылкой — кнопка «Открыть стол» первой строкой
  console.log('4. Кнопка «Открыть стол»');
  лента.событие({
    что: '4', игра: 'дурак', код: 'K003', ктоИмя: 'Аня', ктоНомер: 201,
    кому: [{ номер: 206, наЭкране: false }], ссылка: 'https://t.me/бот/игра?startapp=ABCD-xyz'
  });
  if (!ЛОМАТЬ) {
    const письмо = письмаКому(206)[0];
    const кнопки = (письмо.reply_markup && письмо.reply_markup.inline_keyboard) || [];
    проверить(кнопки.length === 2, 'со ссылкой в письме должно быть две кнопки');
    проверить(кнопки[0] && кнопки[0][0] && кнопки[0][0].url === 'https://t.me/бот/игра?startapp=ABCD-xyz',
      'кнопка «Открыть стол» обязана вести на присланную ссылку');
    проверить(кнопки[1] && кнопки[1][0] && кнопки[1][0].callback_data === 'не-звать',
      'кнопка «Не звать меня» обязана идти следующей строкой');
  }

  // --- 5. Предел: тот же тип тому же адресату на тот же стол — не чаще раза в 60 с
  console.log('5. Предел «раз в 60 секунд»');
  лента.событие({
    что: '4', игра: 'дурак', код: 'K004', ктоИмя: 'Аня', ктоНомер: 201,
    кому: [{ номер: 207, наЭкране: false }]
  });
  проверить(письмаКому(207).length === 1, 'первое письмо этого типа должно дойти');
  лента.событие({
    что: '4', игра: 'дурак', код: 'K004', ктоИмя: 'Аня', ктоНомер: 201,
    кому: [{ номер: 207, наЭкране: false }]
  });
  проверить(письмаКому(207).length === 1,
    'повтор того же типа тому же человеку за тем же столом раньше 60 с не должен слать второе письмо');
  продвинутьВремя(61 * 1000);
  лента.событие({
    что: '4', игра: 'дурак', код: 'K004', ктоИмя: 'Аня', ктоНомер: 201,
    кому: [{ номер: 207, наЭкране: false }]
  });
  проверить(письмаКому(207).length === 2, 'через 61 секунду то же письмо должно уйти снова');

  // --- 6. Предел: не больше 10 писем в час одному человеку
  console.log('6. Предел «10 писем в час»');
  const АДРЕСАТ_ЧАСА = 999;
  for (let счёт = 0; счёт < 10; счёт++) {
    лента.событие({
      что: '4', игра: 'дурак', код: 'H' + счёт, ктоИмя: 'Аня', ктоНомер: 201,
      кому: [{ номер: АДРЕСАТ_ЧАСА, наЭкране: false }]
    });
  }
  проверить(письмаКому(АДРЕСАТ_ЧАСА).length === 10, 'за час должно пройти ровно 10 писем');
  лента.событие({
    что: '4', игра: 'дурак', код: 'H-одиннадцатый', ктоИмя: 'Аня', ктоНомер: 201,
    кому: [{ номер: АДРЕСАТ_ЧАСА, наЭкране: false }]
  });
  проверить(письмаКому(АДРЕСАТ_ЧАСА).length === 10,
    '11-е письмо за тот же час одному человеку обязано быть отклонено');

  // --- 7. 403 при отправке ставит «ботНеПишет»
  console.log('7. Отказ Telegram (403) запоминается');
  комуНеПишем.add(301);
  лента.событие({
    что: '3в', игра: 'дурак', код: 'K007', ктоИмя: 'Боря', ктоНомер: 302,
    кому: [{ номер: 301, наЭкране: false }]
  });
  await дождатьсяОбработки();
  проверить(запретыИзЗа403.get(301) === 'ботНеПишет',
    'ответ Telegram 403 обязан вызвать запретить(номер, «ботНеПишет»)');

  // --- 8. Посадка-призрак: ещёЗаСтолом=false перед отправкой — письма не будет
  console.log('8. Посадка-призрак (задержка 5 с у писем 2 и 3б)');
  лента.событие({
    что: '2', игра: 'дурак', код: 'GHOST1', ктоИмя: 'Боря', ктоНомер: 401,
    кому: [{ номер: 402, наЭкране: false }], занятоМест: 2, всегоМест: 4
  });
  проверить(письмаКому(402).length === 0, 'до истечения задержки письмо ещё не должно быть отправлено');
  ушедшиеСоСтола.add('GHOST1:401');   // тот, кто вошёл, к моменту отправки уже не за столом
  продвинутьВремя(6000);
  await дождатьсяОбработки();
  проверить(письмаКому(402).length === 0,
    'если посадка откатилась (ещёЗаСтолом=false), письмо после задержки слать нельзя');

  // --- 9. Честная задержанная отправка + точный текст события 2
  console.log('9. Текст события 2: «сел за ваш стол... (N из M)»');
  лента.событие({
    что: '2', игра: 'дурак', код: 'SIT1', ктоИмя: 'Боря', ктоНомер: 501,
    кому: [{ номер: 502, наЭкране: false }], занятоМест: 2, всегоМест: 4
  });
  проверить(письмаКому(502).length === 0, 'письмо события 2 должно уйти не раньше задержки в 5 секунд');
  продвинутьВремя(5000);
  await дождатьсяОбработки();
  const письмоСел = письмаКому(502)[0];
  if (!ЛОМАТЬ) {
    const образец = лента.собратьПисьмо({
      что: '2', игра: 'дурак', ктоИмя: 'Боря', занятоМест: 2, всегоМест: 4
    });
    проверить(письмоСел.text === образец.текст, 'текст письма разошёлся с тем, что собирает сама лента');
    проверить(письмоСел.text === 'Боря — за вашим столом в подкидного дурака (2 из 4). ' +
      'Откройте игру, чтобы не пропустить начало.', 'текст события 2 не совпал с образцом из таблицы плана');
  }

  // --- 10. Текст события 3а — без «ваш ход» (3а тоже откладывается на 5 с, замечание 1)
  console.log('10. Текст события 3а: без «ваш ход»');
  лента.событие({
    что: '3а', игра: 'дурак', код: 'TWO1', ктоИмя: 'Боря', ктоНомер: 601,
    кому: [{ номер: 602, наЭкране: false }]
  });
  продвинутьВремя(5000);
  await дождатьсяОбработки();
  const письмоНачалось = письмаКому(602)[0];
  if (!ЛОМАТЬ) {
    проверить(письмоНачалось.text === 'Боря за вашим столом — партия в дурака началась.',
      'текст события 3а разошёлся с решением штаба (без «ваш ход»)');
    проверить(письмоНачалось.text.indexOf('ваш ход') === -1,
      'текст события 3а не должен содержать «ваш ход» — эту часть по решению владельца не делаем');
  }

  // --- 11. Текст события 3б — склонение слова «место»
  console.log('11. Текст события 3б: «все N мест заняты»');
  лента.событие({
    что: '3б', игра: 'дурак', код: 'FULL1', ктоИмя: 'Витя', ктоНомер: 701,
    кому: [{ номер: 702, наЭкране: false }], всегоМест: 4
  });
  продвинутьВремя(5000);
  await дождатьсяОбработки();
  const письмоСобрались = письмаКому(702)[0];
  if (!ЛОМАТЬ) {
    проверить(письмоСобрались.text === 'Стол собрался: все 4 места заняты. Нажмите «Начать».',
      'текст события 3б не совпал с образцом (число мест «4» → «места»)');
  }
  лента.событие({
    что: '3б', игра: 'дурак', код: 'FULL2', ктоИмя: 'Витя', ктоНомер: 703,
    кому: [{ номер: 704, наЭкране: false }], всегоМест: 6
  });
  продвинутьВремя(5000);
  await дождатьсяОбработки();
  const письмоШестьМест = письмаКому(704)[0];
  if (!ЛОМАТЬ) {
    проверить(письмоШестьМест.text.indexOf('все 6 мест заняты') !== -1,
      'число мест «6» должно склоняться как «мест», а не «места»');
  }

  // --- 12. Текст события 3в
  console.log('12. Текст события 3в');
  лента.событие({
    что: '3в', игра: 'дурак', код: 'START1', ктоИмя: 'Хозяин', ктоНомер: 801,
    кому: [{ номер: 802, наЭкране: false }]
  });
  const письмоНачал = письмаКому(802)[0];
  if (!ЛОМАТЬ) {
    проверить(письмоНачал.text === 'Хозяин стола начал партию в дурака — вас ждут.',
      'текст события 3в не совпал с образцом из таблицы плана');
  }

  // --- 13. Другие игры не ломают словарь (закрытый набор: дурак, шашки, нарды, шахматы)
  console.log('13. Название игры для шашек, нард и шахмат');
  for (const игра of ['шашки', 'нарды', 'шахматы']) {
    const письмо = лента.собратьПисьмо({ что: '3в', игра: игра, ктоИмя: 'Хозяин' });
    проверить(письмо.текст.indexOf('в ' + игра) !== -1,
      'название игры «' + игра + '» должно быть в тексте события 3в как есть');
  }
  const письмоНеизвестной = лента.собратьПисьмо({ что: '3в', игра: 'неизвестная-игра', ктоИмя: 'Хозяин' });
  проверить(письмоНеизвестной.текст.indexOf('дурака') !== -1,
    'незнакомая игра обязана падать в словарь запасным словом «дурак», а не пробрасывать чужой текст');

  // --- 14. Хозяин может законно совпасть с «вызвавшим» (см. хозяинНомер)
  console.log('14. хозяинНомер: хозяин не исключается сам из себя');
  лента.событие({
    что: '3б', игра: 'дурак', код: 'SELF1', ктоИмя: 'Хозяин', ктоНомер: 901, хозяинНомер: 901,
    кому: [{ номер: 901, наЭкране: false }], всегоМест: 4
  });
  продвинутьВремя(5000);
  await дождатьсяОбработки();
  проверить(письмаКому(901).length === 1,
    'если хозяин сам оказался тем, кто вызвал событие, письмо ему всё равно должно уйти');

  /* -----------------------------------------------------------------
     Дальше — сверки на замечания ревьюера (по одному пункту на блок).
     ----------------------------------------------------------------- */

  // --- 15. Замечание 1: письмо 3а тоже откладывается на 5 с и не уходит при откате
  console.log('15. Замечание 1: событие 3а тоже откладывается и не уходит при откате');
  лента.событие({
    что: '3а', игра: 'дурак', код: 'GHOST2', ктоИмя: 'Оля', ктоНомер: 1011,
    кому: [{ номер: 1012, наЭкране: false }]
  });
  проверить(письмаКому(1012).length === 0,
    'событие 3а обязано откладываться на 5 с, а не уходить мгновенно, как 2 и 3б');
  ушедшиеСоСтола.add('GHOST2:1011');   // тот, кто «сел вторым», к моменту отправки уже не за столом
  продвинутьВремя(6000);
  await дождатьсяОбработки();
  проверить(письмаКому(1012).length === 0,
    'если «второй сел» откатилось, письмо 3а после задержки слать нельзя, как и письма 2/3б');

  // --- 16. Замечание 2: призрак не тратит предел — настоящее письмо позже всё равно доходит
  console.log('16. Замечание 2: призрачное письмо не тратит предел «раз в 60 с»');
  лента.событие({
    что: '2', игра: 'дурак', код: 'PRED1', ктоИмя: 'Женя', ктоНомер: 1021,
    кому: [{ номер: 1022, наЭкране: false }], занятоМест: 2, всегоМест: 4
  });
  ушедшиеСоСтола.add('PRED1:1022');    // адресат «ушёл» — письмо-призрак должно быть отменено
  продвинутьВремя(5000);
  await дождатьсяОбработки();
  проверить(письмаКому(1022).length === 0, 'призрачное письмо (адресат ушёл до отправки) не должно уйти');
  ушедшиеСоСтола.delete('PRED1:1022'); // ложная тревога снята — на самом деле человек остался
  продвинутьВремя(6000);
  лента.событие({
    что: '2', игра: 'дурак', код: 'PRED1', ктоИмя: 'Женя', ктоНомер: 1021,
    кому: [{ номер: 1022, наЭкране: false }], занятоМест: 3, всегоМест: 4
  });
  продвинутьВремя(5000);
  await дождатьсяОбработки();
  проверить(письмаКому(1022).length === 1,
    'отменённое перепроверкой письмо не должно было потратить предел 60 с — настоящее письмо позже обязано дойти');

  // --- 17. Замечание 3: у вызвавшего без номера «ещё за столом» не проверяем — письмо идёт
  console.log('17. Замечание 3: вызвавший без номера — перепроверку вызвавшего пропускаем, письмо уходит');
  лента.событие({
    что: '2', игра: 'дурак', код: 'NONUM1', ктоИмя: 'Аноним',
    кому: [{ номер: 1031, наЭкране: false }], занятоМест: 1, всегоМест: 4
  });
  продвинутьВремя(5000);
  await дождатьсяОбработки();
  проверить(письмаКому(1031).length === 1,
    'у события без номера вызвавшего (ктоНомер ≤ 0) перепроверка «ещё за столом» для него не делается, письмо должно дойти');

  // --- 18. Замечание 4: исключение «адресат = вызвавший, если он хозяин» — только для 3б
  console.log('18. Замечание 4: самому себе как хозяину — только у события 3б, не у остальных');
  лента.событие({
    что: '3а', игра: 'дурак', код: 'SELF2', ктоИмя: 'Дима', ктоНомер: 1041, хозяинНомер: 1041,
    кому: [{ номер: 1041, наЭкране: false }]
  });
  продвинутьВремя(6000);
  await дождатьсяОбработки();
  проверить(письмаКому(1041).length === 0,
    'у события 3а совпадение адресата с вызвавшим не прощается даже при переданном хозяинНомер — самому себе не пишем');

  // --- 19. Замечание 5: уЭкрана — вернулся к экрану за время задержки, письма нет
  console.log('19. Замечание 5: адресат вернулся к экрану за время задержки — письма нет');
  лента.событие({
    что: '3б', игра: 'дурак', код: 'BACK1', ктоИмя: 'Лена', ктоНомер: 1051,
    кому: [{ номер: 1052, наЭкране: false }], всегоМест: 4
  });
  вернулисьКЭкрану.add('BACK1:1052');
  продвинутьВремя(5000);
  await дождатьсяОбработки();
  проверить(письмаКому(1052).length === 0,
    'адресат успел вернуться к экрану (уЭкрана=true) за время задержки — письмо слать не нужно');

  // --- 20. Замечание 6: исключение внутри отложенного дела не должно ронять процесс
  console.log('20. Замечание 6: бросающая зависимость внутри отложенного дела — процесс жив');
  лента.подключить({
    отправить: поддельноеОтправить,
    почемуНеЗвать: поддельноеПочемуНеЗвать,
    запретить: поддельноеЗапретить,
    ещёЗаСтолом: function () { throw new Error('нарочная беда внутри отложенного дела'); },
    уЭкрана: поддельноеУЭкрана,
    сейчас: мокСейчас,
    отложить: мокОтложить
  });
  лента.событие({
    что: '2', игра: 'дурак', код: 'BOOM1', ктоИмя: 'Игорь', ктоНомер: 1061,
    кому: [{ номер: 1062, наЭкране: false }], занятоМест: 1, всегоМест: 4
  });
  let процессУпалБыОтДела = false;
  try {
    продвинутьВремя(5000);
  } catch (беда) {
    процессУпалБыОтДела = true;
  }
  проверить(!процессУпалБыОтДела,
    'исключение внутри отложенного дела обязано быть поймано try/catch внутри ленты, а не всплывать наружу');
  await дождатьсяОбработки();
  // вернуть честные зависимости
  лента.подключить({
    отправить: поддельноеОтправить,
    почемуНеЗвать: поддельноеПочемуНеЗвать,
    запретить: поддельноеЗапретить,
    ещёЗаСтолом: поддельноеЕщёЗаСтолом,
    уЭкрана: поддельноеУЭкрана,
    сейчас: мокСейчас,
    отложить: мокОтложить
  });

  // --- 21. Сбой проверки у ОДНОГО адресата не должен лишать письма остальных
  console.log('21. Сбой у одного адресата не мешает письму остальным получателям');
  const ПРОБЛЕМНЫЙ_КЛЮЧ = 'MULTI1:2072';
  лента.подключить({
    отправить: поддельноеОтправить,
    почемуНеЗвать: поддельноеПочемуНеЗвать,
    запретить: поддельноеЗапретить,
    ещёЗаСтолом: function (код, номер) {
      if (код + ':' + номер === ПРОБЛЕМНЫЙ_КЛЮЧ) throw new Error('нарочная беда у одного адресата');
      return поддельноеЕщёЗаСтолом(код, номер);
    },
    уЭкрана: поддельноеУЭкрана,
    сейчас: мокСейчас,
    отложить: мокОтложить
  });
  лента.событие({
    что: '2', игра: 'дурак', код: 'MULTI1', ктоИмя: 'Соня', ктоНомер: 2071,
    кому: [{ номер: 2072, наЭкране: false }, { номер: 2073, наЭкране: false }],
    занятоМест: 2, всегоМест: 4
  });
  продвинутьВремя(5000);
  await дождатьсяОбработки();
  проверить(письмаКому(2072).length === 0,
    'адресату, у которого перепроверка упала с ошибкой, письмо не уходит — честная осторожность');
  проверить(письмаКому(2073).length === 1,
    'сбой проверки у одного адресата не должен лишать письма остальных получателей того же события');
  // вернуть честные зависимости для порядка
  лента.подключить({
    отправить: поддельноеОтправить,
    почемуНеЗвать: поддельноеПочемуНеЗвать,
    запретить: поддельноеЗапретить,
    ещёЗаСтолом: поддельноеЕщёЗаСтолом,
    уЭкрана: поддельноеУЭкрана,
    сейчас: мокСейчас,
    отложить: мокОтложить
  });

  /* -----------------------------------------------------------------
     22. Тексты писем верны для любого рода имени: род по имени из
     Telegram не определить («Лена» звучит и как женское, и — реже,
     но бывает — как обиходное сокращение мужского), поэтому письмо не
     имеет права зависеть от рода. Ищем явный список глаголов
     прошедшего времени, которые по-русски согласуются с родом имени
     («Лена СЕЛ» — мужской род, «Лена СЕЛА» — женский, и оба неверны
     для реального человека, чей род письму неизвестен): если такой
     глагол стоит сразу после имени — это и есть баг «Лена сел».
     ----------------------------------------------------------------- */
  console.log('22. Ни один текст не содержит «Имя + глагол прошедшего времени, согласуемый по роду»');
  const ЗАПРЕЩЁННЫЕ_ГЛАГОЛЫ = [
    'сел', 'села', 'пришёл', 'пришла', 'вошёл', 'вошла',
    'начал', 'начала', 'занял', 'заняла', 'предложил', 'предложила',
    'позвал', 'позвала', 'сыграл', 'сыграла', 'открыл', 'открыла'
  ];

  /** true, если сразу после имени в тексте стоит один из запрещённых
   *  глаголов — «сразу после» значит без букв между ними, но конец
   *  проверяем по границе слова БЕЗ \b (в кириллице он не работает,
   *  см. tests/правила проверок): следующий символ после глагола не
   *  должен быть буквой, иначе это часть более длинного слова. */
  function содержитЗапрещённыйГлаголПриИмени(текст, имя) {
    for (const глагол of ЗАПРЕЩЁННЫЕ_ГЛАГОЛЫ) {
      const комбинация = имя + ' ' + глагол;
      let позиция = текст.indexOf(комбинация);
      while (позиция !== -1) {
        const следующийСимвол = текст[позиция + комбинация.length] || ' ';
        if (!/[а-яёА-ЯЁa-zA-Z]/.test(следующийСимвол)) return глагол;
        позиция = текст.indexOf(комбинация, позиция + 1);
      }
    }
    return null;
  }

  const событияСИменем = [
    { что: '2', занятоМест: 2, всегоМест: 4 },
    { что: '3а' },
    { что: '3б', всегоМест: 4 },
    { что: '3в' },
    { что: '4' }
  ];
  for (const имяПроверки of ['Лена', 'Боря']) {
    for (const шаблон of событияСИменем) {
      const данные = Object.assign({ игра: 'дурак', ктоИмя: имяПроверки }, шаблон);
      const письмо = лента.собратьПисьмо(данные);
      const найденныйГлагол = содержитЗапрещённыйГлаголПриИмени(письмо.текст, имяПроверки);
      проверить(!найденныйГлагол,
        'событие «' + шаблон.что + '» при имени «' + имяПроверки + '» содержит запрещённый оборот «' +
        имяПроверки + ' ' + найденныйГлагол + '»: текст «' + письмо.текст + '»');
    }
  }
}

