/** Выполняется В СТРАНИЦЕ: собирает настоящий вид стола и отдаёт его как от сети.
    Для окна итога играем несколько раундов, чтобы сводка «Все раунды» была не пустой. */
function подсунутьВид(св) {
  const П = window.ДоминоПравила, Б = window.ДоминоБот;
  const заморозка = Date.now();
  Date.now = function () { return заморозка; };   // число на экране не убегает
  const мест = св.мест || 3;
  let g;
  for (let попытка = 0; попытка < 40; попытка++) {
    g = П.создать(мест, 100, П.колода());
    if (св.фаза === 'игра') {
      for (let i = 0; i < 6 && g.фаза === 'игра'; i++) { const кто = g.ход; П.действие(g, кто, Б.ход(П.вид(g, кто), 'обычный')); }
      if (g.фаза === 'игра') { g.ход = св.ход === 'я' ? 0 : 1; break; }
    } else {
      for (let шаг = 0; шаг < 20000 && g.фаза !== 'конец'; шаг++) {
        if (g.фаза === 'игра') { const кто = g.ход; П.действие(g, кто, Б.ход(П.вид(g, кто), 'обычный')); }
        else if (св.фаза === 'итог' && g.раунд >= 3) break;
        else П.следующий(g, П.колода());
      }
      if (g.фаза === св.фаза && g.история.length >= 2) break;
    }
  }
  const вид = П.вид(g, 0);
  вид.имена = ['Вы', 'Александра', 'Мария', 'Константин'].slice(0, мест);
  вид.местаИгроков = вид.имена.map(function (_, i) { return i; });
  вид.можноПродолжить = !св.гость;   // гость не может начать раунд — ждёт хозяина
  const v = { игра: 'домино', код: 'ТЕСТ', этап: 'партия', версия: 1, номерСобытия: 1, событие: '', сыграноПартий: 0,
    яХочуЕщё: Boolean(св.яХочуЕщё), соперникХочетЕщё: false, соперникПришёл: true, соперникНаСвязи: true, соперникУшёл: false,
    имяСоперника: 'Александра', завершена: false, яХожу: вид.ход === 0, знакиВниманияЕсть: true, броскиЕсть: true,
    мест, мойНомер: 0, яХозяин: !св.гость, можноНачать: false, парами: false, домино: вид, остатокСекундНаХод: св.секунд };
  if (св.событие) { v.видСобытия = 'ход-по-времени'; v.событие = 'Александра: время вышло — ход сделал бот'; }
  window.ИграПоСети.показатьВид(v);
  return { фаза: вид.фаза, ход: вид.ход, раундов: вид.история.length };
}

/** Выполняется В СТРАНИЦЕ: замеры стола (пилюля, плашка, подсказка). */
function замеритьСтол() {
  const видно = function (у) {
    if (!у) return false;
    const с = getComputedStyle(у), р = у.getBoundingClientRect();
    return с.display !== 'none' && с.visibility !== 'hidden' && р.width > 0 && р.height > 0 && !у.classList.contains('скрыт');
  };
  const прям = function (у) { const р = у.getBoundingClientRect(); return { x: р.left, y: р.top, r: р.right, b: р.bottom, w: р.width, h: р.height }; };
  const W = document.documentElement.clientWidth, H = window.innerHeight;
  const итог = { W, H, прокруткаВбок: document.documentElement.scrollWidth - W };
  const пил = document.getElementById('дом-отсчёт');
  итог.пилюляЕсть = Boolean(пил); итог.пилюляВидна = видно(пил);
  if (пил && итог.пилюляВидна) {
    const с = getComputedStyle(пил);
    итог.пилюля = прям(пил); итог.пилюляТекст = пил.textContent.trim(); итог.пилюляКласс = пил.className;
    итог.мало = пил.classList.contains('дом-отсчёт--мало');
    итог.фон = с.backgroundColor; итог.цветТекста = с.color;
  }
  const плашка = document.getElementById('дом-очередь');
  итог.плашкаВидна = видно(плашка);
  if (итог.плашкаВидна) { итог.плашка = прям(плашка); итог.плашкаКласс = плашка.className; }
  const кто = document.getElementById('дом-кто');
  if (кто && видно(кто)) {
    const диап = document.createRange(); диап.selectNodeContents(кто);
    const р = диап.getBoundingClientRect();
    итог.кто = { x: р.left, y: р.top, r: р.right, b: р.bottom }; итог.ктоТекст = кто.textContent.trim();
  }
  const подс = document.getElementById('дом-подсказка');
  итог.подсказкаВидна = видно(подс);
  if (итог.подсказкаВидна) {
    итог.подсказка = прям(подс); итог.подсказкаТекст = подс.textContent.trim();
    итог.подсказкаОбрезана = подс.scrollWidth > подс.clientWidth + 1 || подс.scrollHeight > подс.clientHeight + 1;
    const с = getComputedStyle(подс);
    итог.подсказкаСтиль = { перенос: с.whiteSpace, обрезка: с.textOverflow, переполнение: с.overflow, строк: Math.round(подс.getBoundingClientRect().height / (parseFloat(с.lineHeight) || parseFloat(с.fontSize) * 1.2)) };
  }
  return итог;
}

/** Выполняется В СТРАНИЦЕ: замеры окна итога — части, кнопки, середина, крутилка, прокрутка страницы. */
function замеритьОкно() {
  const видно = function (у) {
    if (!у) return false;
    const с = getComputedStyle(у), р = у.getBoundingClientRect();
    return с.display !== 'none' && с.visibility !== 'hidden' && р.width > 0 && р.height > 0 && !у.classList.contains('скрыт');
  };
  const прям = function (у) { const р = у.getBoundingClientRect(); return { x: р.left, y: р.top, r: р.right, b: р.bottom, w: р.width, h: р.height }; };
  const корень = document.scrollingElement || document.documentElement;
  const м = { W: document.documentElement.clientWidth, H: window.innerHeight, прокруткаВбок: document.documentElement.scrollWidth - document.documentElement.clientWidth,
    прокруткаСтраницы: Math.round(Math.max(window.scrollY || 0, корень.scrollTop || 0, document.body.scrollTop || 0)), узлы: {} };
  const окно = document.getElementById('дом-результат');
  м.открыто = Boolean(окно && окно.open);
  if (!м.открыто) return м;
  м.окно = прям(окно);
  ['дом-итог-шапка', 'дом-итог-середина', 'дом-итог-подвал', 'дом-итог-заголовок', 'дом-итог-отсчёт', 'дом-дальше', 'дом-посмотреть', 'дом-в-лобби'].forEach(function (id) {
    const у = document.getElementById(id);
    const з = { есть: Boolean(у), виден: видно(у) };
    if (з.виден) {
      Object.assign(з, прям(у));
      з.текст = у.textContent.trim();
      з.обрезан = у.scrollWidth > у.clientWidth;
      з.ширины = у.scrollWidth + ' > ' + у.clientWidth;
      const ц = document.elementFromPoint((з.x + з.r) / 2, (з.y + з.b) / 2);
      з.сверху = Boolean(ц && (ц === у || у.contains(ц)));
      з.вЦентре = ц ? (ц.id || ц.className || ц.tagName) : 'ничего';
    }
    м.узлы[id] = з;
  });
  const середина = document.getElementById('дом-итог-середина');
  if (середина) м.середина = { сверху: Math.round(середина.scrollTop), всего: середина.scrollHeight, видно: середина.clientHeight };
  if (середина) {
    const сс = getComputedStyle(середина);
    м.края = { выше: середина.classList.contains('дом-итог-середина--выше'), ниже: середина.classList.contains('дом-итог-середина--ниже'),
      маска: сс.maskImage || сс.webkitMaskImage || 'none' };
  }
  // Строка отсчёта: верх последней цифры и верх «с» — «с» не должна уехать на свою строку.
  const отсчёт = document.getElementById('дом-итог-отсчёт'), текстУзел = отсчёт && отсчёт.firstChild;
  if (видно(отсчёт) && текстУзел && текстУзел.nodeType === 3) {
    const т = текстУзел.textContent, иС = т.lastIndexOf('с');
    let иЧ = иС - 1;
    while (иЧ >= 0 && !/[0-9]/.test(т[иЧ])) иЧ--;
    if (иС > 0 && иЧ >= 0) {
      const верх = function (и) { const д = document.createRange(); д.setStart(текстУзел, и); д.setEnd(текстУзел, и + 1); return д.getBoundingClientRect().top; };
      м.сиротка = { верхЧисла: верх(иЧ), верхС: верх(иС) };
    }
  }
  const ф = document.activeElement;
  м.фокус = ф ? (ф.id || ф.tagName) : 'нет';
  м.фокусВСередине = Boolean(середина && ф && середина.contains(ф));
  // Последняя строка «Все раунды и подсчёт»: закрытая сводка — её заголовок, раскрытая — последний раунд.
  const сводка = document.querySelector('#дом-итог-середина details');
  м.сводкаЕсть = Boolean(сводка); м.сводкаОткрыта = Boolean(сводка && сводка.open);
  if (сводка) {
    const строки = сводка.open ? Array.from(document.querySelectorAll('#дом-раунды > *')) : [сводка.querySelector('summary')].filter(Boolean);
    м.строкСводки = строки.length;
    const последняя = строки[строки.length - 1];
    if (последняя) { м.последняя = прям(последняя); м.последняяТекст = последняя.textContent.trim().slice(0, 40); }
  }
  // Крутилка «Ждём …»: псевдоэлемент нельзя померить напрямую — правый край слов + её отступ, ширина и рамка.
  const дальше = document.getElementById('дом-дальше');
  м.ждём = Boolean(дальше && дальше.classList.contains('дом-ждём'));
  if (м.ждём) {
    const п = getComputedStyle(дальше, '::after'), ск = getComputedStyle(дальше), к = дальше.getBoundingClientRect();
    const диап = document.createRange(); диап.selectNodeContents(дальше);
    const слова = диап.getBoundingClientRect();
    const рамка = п.boxSizing === 'border-box' ? 0 : (parseFloat(п.borderLeftWidth) || 0) + (parseFloat(п.borderRightWidth) || 0);
    м.крутилка = { показана: п.display !== 'none' && п.content !== 'none' && п.content !== 'normal', ширина: parseFloat(п.width) || 0,
      правый: слова.right + (parseFloat(п.marginLeft) || 0) + (parseFloat(п.width) || 0) + рамка,
      предел: к.right - (parseFloat(ск.paddingRight) || 0) - (parseFloat(ск.borderRightWidth) || 0) };
  }
  return м;
}

