/* ===== Проверка ===== */

let всеПроверки = 0;
let провалы = 0;

function проверить(описание, условие) {
  всеПроверки++;
  if (условие) {
    console.log('  ✓ ' + описание);
  } else {
    console.log('  ✗ ' + описание);
    провалы++;
  }
}

async function пройти() {
  // Проверяем первую половину цепочки — дурак-путь.js
  console.log('');
  console.log('=== Проверка 1: дурак-путь.js вызывает позвать с открытый: true ===');

  let кодМастера;
  if (ЛОМАТЬ_МАСТЕРА) {
    // Копируем оригинальный файл и удаляем поле открытый: true
    const оригинал = fs.readFileSync(path.join(КОРЕНЬ, 'js/дурак-путь.js'), 'utf8');
    const поломанный = оригинал.replace(
      /Object\.assign\(\{\}, ответ\.стол, \{ открытый: true \}\)/,
      'Object.assign({}, ответ.стол)'
    );
    const копияПути = path.join(ВРЕМЕННАЯ_ПАПКА, 'дурак-путь.js');
    fs.writeFileSync(копияПути, поломанный, 'utf8');
    кодМастера = поломанный;
    console.log('*** ЛОМАЮЩИЙ ЗАПУСК МАСТЕРА: удаляем открытый: true из дурак-путь.js ***');
  } else {
    кодМастера = fs.readFileSync(path.join(КОРЕНЬ, 'js/дурак-путь.js'), 'utf8');
  }

  const естьВызов = /позвать\s*\(\s*'создатьКомнату'\s*,\s*Object\.assign\([^)]*\{\s*открытый\s*:\s*true\s*\}/.test(кодМастера);
  проверить('дурак-путь.js:1017 вызывает позвать с открытый: true', естьВызов);

  if (!естьВызов) {
    console.log('    Не найдена строка: позвать(\'создатьКомнату\', Object.assign(..., { открытый: true }))');
  }

  console.log('');
  console.log('=== Проверка 2: сеть.js доносит открытый: true в запрос ===');

  // Устанавливаем адрес сервера
  память.set('server_address', 'http://127.0.0.1:8765');

  // Загружаем js/сеть.js (может быть из копии, если --сломать)
  let сетевойКод;
  if (ЛОМАТЬ) {
    const сетьПуть = path.join(ВРЕМЕННАЯ_ПАПКА, 'сеть.js');
    // Копируем оригинальный файл в временную папку
    const оригинал = fs.readFileSync(path.join(КОРЕНЬ, 'js/сеть.js'), 'utf8');
    // Удаляем строку, которая проверяет открытый
    const поломанный = оригинал.replace(
      /if \(выборСтола\.открытый\) тело\.открытый = true;/,
      ''
    );
    fs.writeFileSync(сетьПуть, поломанный, 'utf8');
    сетевойКод = поломанный;
    console.log('*** ЛОМАЮЩИЙ ЗАПУСК: удаляем проверку открытого из сеть.js ***');
  } else if (ЛОМАТЬ_МАСТЕРА) {
    // При ломании мастера используем оригинальный сеть.js
    сетевойКод = fs.readFileSync(path.join(КОРЕНЬ, 'js/сеть.js'), 'utf8');
  } else {
    сетевойКод = fs.readFileSync(path.join(КОРЕНЬ, 'js/сеть.js'), 'utf8');
  }

  // Загружаем код в vm
  try {
    vm.runInNewContext(сетевойКод, окружение, { filename: 'js/сеть.js' });
  } catch (ошибка) {
    console.log('Ошибка при загрузке js/сеть.js: ' + (ошибка && ошибка.message || ошибка));
    провалы++;
    return;
  }

  проверить('js/сеть.js загружен в vm', окно.Сеть && typeof окно.Сеть === 'object');
  проверить('Сеть.создатьКомнату существует',
    окно.Сеть && typeof окно.Сеть.создатьКомнату === 'function');

  if (!окно.Сеть || typeof окно.Сеть.создатьКомнату !== 'function') {
    console.log('Не удалось загрузить Сеть.создатьКомнату, тест прерван');
    провалы++;
    return;
  }

  // Вызываем создатьКомнату с параметром открытый: true
  перехваченныеЗапросы = [];
  сколькоЗапросов = 0;

  const результат = await окно.Сеть.создатьКомнату({ открытый: true });

  проверить('Функция создатьКомнату вернула результат', результат && typeof результат === 'object');
  проверить('Был сделан запрос на сервер', сколькоЗапросов > 0);

  // Проверяем, что запрос был к /создать
  const запросКСоздать = перехваченныеЗапросы.find(з => з.путь === '/создать');
  проверить('Запрос к /создать был отправлен', запросКСоздать !== undefined);

  if (запросКСоздать) {
    console.log('    Тело запроса: ' + JSON.stringify(запросКСоздать.тело));
    проверить('В теле запроса есть поле открытый: true',
      запросКСоздать.тело && запросКСоздать.тело.открытый === true);

    // Это главная проверка
    if (!запросКСоздать.тело || запросКСоздать.тело.открытый !== true) {
      console.log('    БЕДА: поле открытый отсутствует или не равно true!');
      console.log('    Это означает, что стол не попадёт в список открытых и');
      console.log('    соперника, ищущего игру по списку, никто не найдёт.');
    }
  }
}

пройти().then(function () {
  // Очистить временную папку
  try {
    if (fs.existsSync(ВРЕМЕННАЯ_ПАПКА)) {
      const файлы = fs.readdirSync(ВРЕМЕННАЯ_ПАПКА);
      for (const файл of файлы) {
        fs.unlinkSync(path.join(ВРЕМЕННАЯ_ПАПКА, файл));
      }
      fs.rmdirSync(ВРЕМЕННАЯ_ПАПКА);
    }
  } catch (е) {
    // Молчим, если не удалось удалить
  }

  console.log('');
  console.log('Итого проверок: ' + всеПроверки + ', провалов: ' + провалы);
  process.exitCode = провалы > 0 ? 1 : 0;
}).catch(function (сбой) {
  console.log('Проверка сорвалась: ' + (сбой && сбой.stack || сбой));
  process.exitCode = 1;
});
