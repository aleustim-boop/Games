const ТИПЫ = {
  '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8', '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg',
  '.webp': 'image/webp', '.woff2': 'font/woff2', '.mp3': 'audio/mpeg', '.ogg': 'audio/ogg', '.wav': 'audio/wav'
};
function поднятьСтраницы() {
  const с = http.createServer(function (зп, отв) {
    let адрес;
    try { адрес = decodeURIComponent(зп.url.split('?')[0].split('#')[0]); } catch (е) { отв.writeHead(400); отв.end(); return; }
    if (адрес === '/') адрес = '/index.html';
    const части = адрес.split('/').filter(Boolean);
    // папку bot и всё, что начинается с точки (.env, .git), не отдаём никогда
    if (!части.length || части[0].toLowerCase() === 'bot' || части.some(function (ч) { return ч.charAt(0) === '.' || ч === '..'; })) {
      отв.writeHead(403); отв.end('закрыто'); return;
    }
    const файл = path.join(КОРЕНЬ, ...части);
    if (!path.resolve(файл).startsWith(path.resolve(КОРЕНЬ) + path.sep)) { отв.writeHead(403); отв.end(); return; }
    fs.readFile(файл, function (ош, данные) {
      if (ош) { отв.writeHead(404); отв.end('нет'); return; }
      отв.writeHead(200, { 'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'application/octet-stream', 'Cache-Control': 'no-store' });
      отв.end(данные);
    });
  });
  return new Promise(function (готово, беда) {
    с.once('error', беда);
    с.listen(ПОРТ_СТРАНИЦ, '127.0.0.1', function () { готово(с); });
  });
}

