const ОТФИЛЬТРОВАНО_ФОТО = [];
const ОТФИЛЬТРОВАНО_TELEGRAM = [];
const ОТФИЛЬТРОВАНО_403 = [];
async function завестиЗаход(браузер, номерTelegram, имя, ждёмОтказ) {
  const окно = await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
  const страница = await окно.newPage();
  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', function (м) {
    if (м.type() !== 'error') return;
    let где = (м.location && м.location().url) || '';
    try { где = decodeURIComponent(где); } catch (е) { /* как есть */ }
    // Единственное прощаемое: 404 на картинку-аватар по двери /фото/ (у выдуманных игроков фото нет).
    if (м.text() === 'Failed to load resource: the server responded with a status of 404 (Not Found)' &&
        где.indexOf(АДРЕС_СЕРВЕРА + '/фото/') === 0) {
      ОТФИЛЬТРОВАНО_ФОТО.push(где);
      return;
    }
    // Скрипт telegram.org обрывает САМ стенд (иначе он затрёт поддельный Telegram) — это не игра.
    if (м.text() === 'Failed to load resource: net::ERR_FAILED' && где === 'https://telegram.org/js/telegram-web-app.js') {
      ОТФИЛЬТРОВАНО_TELEGRAM.push(где);
      return;
    }
    /* В сценариях отказа сервер НАРОЧНО отвечает 403 на /войти — Chromium
       сам пишет это строкой в консоль. Прощаем только там и только точно её. */
    if (ждёмОтказ && м.text() === 'Failed to load resource: the server responded with a status of 403 (Forbidden)' &&
        где === АДРЕС_СЕРВЕРА + '/войти') {
      ОТФИЛЬТРОВАНО_403.push(где);
      return;
    }
    красные.push('консоль: ' + м.text() + (где ? ' [' + где + ']' : ''));
  });
  await подготовитьПодделку(страница, { версия: '7.10', подпись: initDataДля(номерTelegram, имя) });
  if (КОПИЯ_СЕТИ) {
    const текст = fs.readFileSync(КОПИЯ_СЕТИ);
    await перехватить(страница, /\/js\/сеть\.js(?:\?|$)/, function (путь) {
      путь.fulfill({ status: 200, contentType: 'text/javascript; charset=utf-8', body: текст });
    });
  }
  return { окно, страница, красные };
}

function видно(страница, id) {
  return страница.evaluate(function (имя) {
    const у = document.getElementById(имя);
    if (!у) return false;
    const м = у.getBoundingClientRect();
    if (м.width < 1 || м.height < 1) return false;
    const в = window.getComputedStyle(у);
    return в.display !== 'none' && в.visibility !== 'hidden' && Number(в.opacity) > 0;
  }, id).catch(function () { return false; });
}
async function ждатьВидимости(страница, id, потолокМс) {
  const начало = Date.now();
  while (Date.now() - начало < (потолокМс || 15000)) {
    if (await видно(страница, id)) return Date.now() - начало;
    await спать(100);
  }
  return -1;
}
function текстУзла(страница, id) {
  return страница.evaluate(function (имя) {
    const у = document.getElementById(имя);
    return у ? String(у.textContent || '').replace(/\s+/g, ' ').trim() : null;
  }, id).catch(function () { return null; });
}
async function ждатьТекста(страница, id, нужно, потолокМс) {
  const начало = Date.now();
  let т = null;
  while (Date.now() - начало < (потолокМс || 15000)) {
    т = await текстУзла(страница, id);
    if (т !== null && т.indexOf(нужно) !== -1) return т;
    await спать(100);
  }
  return т;
}
function какойЭкран(страница) {
  return страница.evaluate(function () {
    const в = document.querySelector('.экран--виден');
    return в ? в.id : '(ни одного)';
  }).catch(function () { return '(страница меняется)'; });
}
