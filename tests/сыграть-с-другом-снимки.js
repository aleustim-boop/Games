/* ================== 1. Исправная ссылка в дурака ================== */
async function случайИсправнаяСсылка(браузер, всеКрасные) {
  console.log('\n1. Исправная ссылка в дурака — друг сел без набора кода');
  const хоз = await создать(610001, 'дурак', { мест: 3 });
  проверить('1) стол дурака на троих создан', хоз.номер === 200 && Boolean(хоз.данные.код), JSON.stringify(хоз.данные).slice(0, 200));
  if (хоз.номер !== 200) return;
  const з = await завестиЗаход(браузер, 610002, 'Друг');
  await з.страница.goto(адресСсылки(хвостСсылки('durak', хоз.данные.код)), { waitUntil: 'domcontentloaded' });
  const доКомнаты = await ждатьВидимости(з.страница, 'экран-комнаты', 15000);
  проверить('1) у друга открылся экран комнаты (#экран-комнаты виден)', доКомнаты >= 0, 'на виду: ' + await какойЭкран(з.страница));
  проверить('1) на экране комнаты виден сам стол (#комната)', await видно(з.страница, 'комната'));
  const заголовок = await з.страница.evaluate(function () {
    const у = document.querySelector('#комната .комната__заголовок');
    return у ? у.textContent.trim() : null;
  });
  проверить('1) заголовок «Комната игры» на месте', заголовок === 'Комната игры', String(заголовок));
  проверить('1) экран входа по коду НЕ показан (друг код не набирал)', !(await видно(з.страница, 'экран-входа')));
  проверить('1) сервер: за столом двое — хозяин и друг', сколькоЗаСтолом(хоз.данные.код, хоз.данные.пропуск) === 2,
    'за столом ' + сколькоЗаСтолом(хоз.данные.код, хоз.данные.пропуск));
  сказать('игроки на экране: ' + await текстУзла(з.страница, 'комната-игроки'));
  await снять(з.страница, '1-ссылка-дурак-друг-в-комнате.png');
  всеКрасные.push(...з.красные.map((с) => '[1] ' + с));
  await з.окно.close();
}

/* ================== 2–4. Отказы ================== */
async function проверитьОтказ(браузер, всеКрасные, номер, почему, код, номерДруга, снимок) {
  const з = await завестиЗаход(браузер, номерДруга, 'Опоздавший', true);
  await з.страница.goto(адресСсылки(хвостСсылки('durak', код)), { waitUntil: 'domcontentloaded' });
  const доКнопки = await ждатьВидимости(з.страница, 'кнопка-новый-стол', 15000);
  проверить(номер + ') кнопка «Создать новый стол» (#кнопка-новый-стол) показана', доКнопки >= 0, 'на виду: ' + await какойЭкран(з.страница));
  проверить(номер + ') на кнопке слова «Создать новый стол»', (await текстУзла(з.страница, 'кнопка-новый-стол')) === 'Создать новый стол',
    String(await текстУзла(з.страница, 'кнопка-новый-стол')));
  проверить(номер + ') виден экран входа (#экран-входа)', await видно(з.страница, 'экран-входа'), 'на виду: ' + await какойЭкран(з.страница));
  проверить(номер + ') видно сообщение причины (#сообщение-входа)', await видно(з.страница, 'сообщение-входа'));
  const слова = await текстУзла(з.страница, 'сообщение-входа');
  проверить(номер + ') причина словами: «' + СЛОВА[почему] + '»', слова === СЛОВА[почему], 'на экране: «' + слова + '»');
  проверить(номер + ') кнопка «В лобби» (#кнопка-отказ-в-лобби) показана', await видно(з.страница, 'кнопка-отказ-в-лобби'));
  проверить(номер + ') кнопка «Играть здесь» НЕ показана (это не вход с другого устройства)', !(await видно(з.страница, 'кнопка-играть-здесь')));
  await снять(з.страница, снимок);
  всеКрасные.push(...з.красные.map((с) => '[' + номер + '] ' + с));
  await з.окно.close();
}

