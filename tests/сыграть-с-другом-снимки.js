function initDataДля(номер, имя) {
  const поля = {
    query_id: 'AAСнимки' + номер,
    user: JSON.stringify({ id: номер, first_name: имя || ('Игрок' + номер) }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  const строки = Object.keys(поля).map(function (к) { return к + '=' + поля[к]; }).sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(ТОКЕН).digest();
  поля.hash = crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
  return Object.keys(поля).map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(поля[к]); }).join('&');
}

function запрос(путь, тело) {
  return new Promise(function (готово) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const req = http.request({
      host: '127.0.0.1', port: ПОРТ_КОМНАТ, method: 'POST', path: encodeURI(путь),
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let куски = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (к) { куски += к; });
      ответ.on('end', function () {
        let р = null;
        try { р = JSON.parse(куски); } catch (е) { р = { сырое: куски }; }
        готово({ номер: ответ.statusCode, данные: р || {} });
      });
    });
    req.on('error', function (е) { готово({ номер: 0, данные: { ошибка: String(е.message) } }); });
    req.end(данные);
  });
}
