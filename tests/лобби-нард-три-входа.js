function приготовитьИспорченнуюКопиюВдвоём() {
  const путьКФайлу = path.join(КОРЕНЬ, 'нарды.html');
  const исходник = fs.readFileSync(путьКФайлу, 'utf8');
  const регексКарточкаВдвоём = /<button id="лобби-вдвоём"[\s\S]*?<\/button>\n?/;
  const образецБотаБыло = '<button id="кнопка-бот-вдвоём" type="button" class="кнопка кнопка--мелкая скрыт">Лучше вдвоём на этом устройстве</button>';
  if (!регексКарточкаВдвоём.test(исходник) || !исходник.includes(образецБотаБыло)) {
    console.error('ломающий запуск --сломать-вдвоём сломался: в нарды.html не нашлись ожидаемые узлы ' +
      'карточки «лобби-вдвоём» или «кнопка-бот-вдвоём» — ноль замен, портить нечего (провал, а не пропуск)');
    process.exit(2);
  }
  const испорченный = исходник
    .replace(регексКарточкаВдвоём, '')
    .replace(образецБотаБыло, '<button id="кнопка-бот-вдвоём" type="button" class="кнопка кнопка--мелкая">Лучше вдвоём на этом устройстве</button>');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'нарды-вдвоём-'));
  const копия = path.join(папка, 'нарды.html');
  fs.writeFileSync(копия, испорченный, 'utf8');
  console.log('ломающий запуск --сломать-вдвоём: испорченная копия лежит в ' + копия);
  return { копия, папка };
}

