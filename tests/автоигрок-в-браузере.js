/* =====================================================================
   АВТОИГРОК В БРАУЗЕРЕ — «палец», который сам доигрывает партию.

   Зачем он нужен. Партия компанией из шести человек — это сотни нажатий
   и минуты ожидания ботов. Руками столько не наиграешь, а поломки вроде
   «партия встала и нажать нечего» ловятся только в конце партии.

   Что он делает. Ровно то же, что делал бы человек: смотрит на экран
   (подсказку, кнопки, подсветку карт) и НАЖИМАЕТ настоящие кнопки и карты.
   Во внутренности игры он не лезет и правил не знает — поэтому если игра
   покажет «можете подкинуть», а карту не примет, автоигрок это заметит.

   Как пользоваться (из консоли браузера):
       Автоигрок.начать();                      // играет, пока партия не кончится
       Автоигрок.отчёт();                       // что случилось: итог, поломки
       Автоигрок.стоп();                        // прекратить

   Всё, что показалось поломкой, копится в «Автоигрок.поломки».
   ===================================================================== */

(function () {
  'use strict';

  /* Пауза между «взглядами на экран». Нарочно больше 150 мс: столько игра
     не слышит руку сразу после нажатия кнопки (чтобы «хвост» пальца не сыграл
     карту). Шагай мы чаще — сами бы напоролись на эту глухоту и записали
     несуществующую поломку. */
  const ШАГ = 220;
  const ТЕРПЕНИЕ = 14000;       // сколько ждём, пока на экране хоть что-то изменится
  const ПОТОЛОК_НАЖАТИЙ = 4000; // защита от вечного цикла

  function эл(id) { return document.getElementById(id); }

  /** Играем ли мы сейчас по сети: у сетевой партии есть строка связи. */
  function этоИграПоСети() { return виден(эл('строка-связи')); }

  function виден(узел) {
    if (!узел) return false;
    if (узел.classList.contains('скрыт')) return false;
    const рект = узел.getBoundingClientRect();
    return рект.width > 0 && рект.height > 0;
  }

  function текст(id) {
    const узел = эл(id);
    return узел ? (узел.textContent || '').trim() : '';
  }

  /** Что сейчас написано в строке подсказки (её видит живой игрок). */
  function подсказка() {
    const узел = document.getElementById('подсказка-текст') || эл('подсказка');
    return узел ? (узел.textContent || '').trim() : '';
  }

  /** Слепок экрана: если он не меняется — на экране ничего не происходит. */
  function слепок() {
    const рука = [].map.call(document.querySelectorAll('#карты-человека .карта'),
      function (у) { return у.textContent + '|' + у.className; }).join(',');
    const стол = [].map.call(document.querySelectorAll('#стол .пара'),
      function (у) { return у.textContent + '|' + у.className; }).join(',');
    const плашки = [].map.call(document.querySelectorAll('#соперники .соперник'),
      function (у) { return у.textContent; }).join(',');
    return [подсказка(), рука, стол, плашки, текст('счётчик-бота'),
            текст('счётчик-колоды'), видимыеКнопки()].join('#');
  }

  function видимыеКнопки() {
    return ['кнопка-завершить', 'кнопка-беру', 'кнопка-перевести'].filter(function (id) {
      return виден(эл(id));
    }).map(function (id) { return id + ':' + текст(id); }).join('+');
  }

  const состояние = {
    работает: false,
    нажатий: 0,
    поломки: [],
    журнал: [],
    итог: null,
    прошлыйСлепок: '',
    безДвижения: 0,
    доляПодкидывания: 0.6,
    любитПереводить: false,
    /* Номер запуска. Нужен вот зачем: «начать» вызывают перед каждой партией,
       и если прошлая цепочка шагов ещё жива, по экрану начинают ходить ДВА
       автоигрока сразу. Тогда два нажатия случаются в один и тот же миг,
       второе попадает в окно глухоты после кнопки (игра нарочно не слышит
       руку 150 мс) — и проверка записывает поломку, которой нет.
       Так мы один раз уже чуть не выдали ложную находку. */
    запуск: 0
  };

  function записать(что) {
    состояние.журнал.push(что);
    if (состояние.журнал.length > 400) состояние.журнал.shift();
  }

  function поломка(что, подробности) {
    состояние.поломки.push({ что: что, подсказка: подсказка(),
                             кнопки: видимыеКнопки(), подробности: подробности || '' });
  }

  function тап(узел) {
    if (!узел) return false;
    состояние.нажатий++;
    узел.click();
    return true;
  }

  /** Плашка итога на экране — партия доиграна. */
  function партияДоиграна() {
    const итог = эл('экран-результата');
    return Boolean(итог && итог.classList.contains('экран--виден'));
  }

  /** Один шаг: посмотреть на экран и сделать то, что сделал бы человек. */
  function шаг(моёПоколение) {
    if (!состояние.работает) return;
    // Нас перезапустили — эта цепочка шагов лишняя, тихо расходимся.
    if (моёПоколение !== состояние.запуск) return;
    if (состояние.нажатий > ПОТОЛОК_НАЖАТИЙ) {
      поломка('слишком много нажатий — похоже, партия ходит по кругу');
      состояние.работает = false;
      return;
    }
    if (партияДоиграна()) {
      состояние.итог = {
        заголовок: текст('текст-результата'),
        пояснение: текст('пояснение-результата'),
        рамка: текст('серия-итога')
      };
      состояние.работает = false;
      return;
    }

    const сейчас = слепок();
    if (сейчас === состояние.прошлыйСлепок) состояние.безДвижения += ШАГ;
    else { состояние.безДвижения = 0; состояние.прошлыйСлепок = сейчас; }

    const сделал = походить();
    if (сделал) { состояние.безДвижения = 0; состояние.прошлыйСлепок = ''; }

    if (состояние.безДвижения >= ТЕРПЕНИЕ) {
      поломка('партия встала: за ' + Math.round(ТЕРПЕНИЕ / 1000) +
              ' секунд на экране ничего не изменилось и нажать нечего');
      состояние.работает = false;
      return;
    }
    setTimeout(function () { шаг(моёПоколение); }, ШАГ);
  }

  function картыВРуке(класс) {
    return [].slice.call(document.querySelectorAll('#карты-человека .' + класс));
  }

  /** Сделать один ход, если экран о нём просит. Вернёт true, если нажали. */
  function походить() {
    const беру = эл('кнопка-беру');
    const завершить = эл('кнопка-завершить');
    const перевести = эл('кнопка-перевести');
    const можно = картыВРуке('карта--можно');
    const выбрана = картыВРуке('карта--выбрана');

    // Карта уже поднята — надо указать, что ею бить (или перевести).
    if (выбрана.length > 0) {
      const цели = [].slice.call(document.querySelectorAll('#стол .пара--цель'));
      // Режим «люблю переводить» нужен, чтобы проверить кнопку «Перевести»:
      // обычно автоигрок предпочитает отбиться, и до перевода дело не доходит.
      if (состояние.любитПереводить && виден(перевести)) {
        записать('перевожу картой ' + выбрана[0].textContent);
        return тап(перевести);
      }
      if (цели.length > 0) {
        записать('бью картой ' + выбрана[0].textContent);
        return тап(цели[0]);
      }
      if (виден(перевести)) {
        записать('перевожу картой ' + выбрана[0].textContent);
        return тап(перевести);
      }
      // Поднятой картой ни побить, ни перевести — это уже странно.
      поломкаНеверногоПодъёма(выбрана[0]);
      return тап(выбрана[0]);   // опускаем карту обратно
    }

    // Защита: сначала пробуем отбиться, потом — брать.
    if (виден(беру)) {
      if (можно.length > 0) {
        записать('поднимаю карту ' + можно[0].textContent);
        return тап(можно[0]);
      }
      записать('беру карты');
      return тап(беру);
    }

    // Атака, подкидывание, докидывание. Карту берём случайную из разрешённых:
    // так за много партий проверяется вся подсветка, а не только левый край руки.
    const любая = можно[Math.floor(Math.random() * можно.length)];
    if (можно.length > 0 && Math.random() < состояние.доляПодкидывания) {
      return положитьИПроверить(любая);
    }
    if (виден(завершить)) {
      записать('жму «' + текст('кнопка-завершить') + '»');
      return тап(завершить);
    }
    if (можно.length > 0) {
      return положитьИПроверить(любая);
    }
    return false;   // сейчас ходит не человек — ждём
  }

  /**
   * Положить карту и тут же проверить самое обидное вранье: игра пометила
   * карту зелёной чертой («этой ходить можно»), человек по ней тапнул —
   * а карта осталась в руке. Живой игрок в таком месте тыкает снова и снова
   * и решает, что игра зависла.
   */
  function положитьИПроверить(узел) {
    const подпись = узел.textContent;
    const веер = [].slice.call(document.querySelectorAll('#карты-человека .карта'));
    const место = веер.indexOf(узел);
    const былоВРуке = веер.length;
    const былоНаСтоле = document.querySelectorAll('#стол .пара').length;
    записать('кладу карту ' + подпись);
    тап(узел);
    const сталоВРуке = document.querySelectorAll('#карты-человека .карта').length;
    const сталоНаСтоле = document.querySelectorAll('#стол .пара').length;
    /* В игре по сети ход улетает на сервер, и рука меняется не сразу —
       там такая проверка ловила бы обычное ожидание ответа, а не поломку. */
    if (!этоИграПоСети() && сталоВРуке === былоВРуке && сталоНаСтоле === былоНаСтоле) {
      поломка('карта помечена как разрешённая, но игра её не приняла',
              'карта: ' + подпись + ' (место в руке ' + место + '), ' +
              'в руке было и осталось ' + былоВРуке + '. ' + внутренности(место));
    }
    return true;
  }

  /**
   * Что об этом же миге думает сама игра. Только чтение: ничего не меняем,
   * просто спрашиваем её же мерки, чтобы штабу было с чем идти к коду.
   */
  function внутренности(место) {
    try {
      const глянуть = function (что) { return (0, eval)(что); };
      const партия = глянуть('партия');
      if (!партия) return 'партии в этот миг уже нет';
      const карта = партия.руки.человек[место];
      return 'фаза «' + глянуть('фаза')(партия) + '», ' +
             'слово у «' + глянуть('ктоХодит')(партия) + '», ' +
             'мой ли ход: ' + глянуть('сейчасМойХод')() + ', ' +
             'можно ли подкинуть: ' + глянуть('мнеМожноПодкинуть')() + ', ' +
             'правила про карту: ' + (карта ? глянуть('можноПоложить')(партия, карта) : 'карты нет') + ', ' +
             'рука глуха ещё ' + Math.max(0, глянуть('рукаГлухаДо') - Date.now()) + ' мс';
    } catch (е) {
      return 'заглянуть внутрь не вышло: ' + е;
    }
  }

  function поломкаНеверногоПодъёма(узел) {
    поломка('карта поднялась, но бить ею нечего и кнопки «Перевести» нет',
            'карта: ' + узел.textContent);
  }

  window.Автоигрок = {
    начать: function (доляПодкидывания, любитПереводить) {
      if (typeof доляПодкидывания === 'number') состояние.доляПодкидывания = доляПодкидывания;
      состояние.любитПереводить = Boolean(любитПереводить);
      состояние.работает = true;
      состояние.нажатий = 0;
      состояние.поломки = [];
      состояние.журнал = [];
      состояние.итог = null;
      состояние.прошлыйСлепок = '';
      состояние.безДвижения = 0;
      состояние.запуск++;
      const моёПоколение = состояние.запуск;
      setTimeout(function () { шаг(моёПоколение); }, ШАГ);
      return 'играю';
    },
    стоп: function () { состояние.работает = false; return 'остановился'; },
    работает: function () { return состояние.работает; },
    отчёт: function () {
      return {
        работает: состояние.работает,
        нажатий: состояние.нажатий,
        итог: состояние.итог,
        поломки: состояние.поломки,
        подсказка: подсказка(),
        кнопки: видимыеКнопки(),
        хвостЖурнала: состояние.журнал.slice(-25)
      };
    }
  };
})();
