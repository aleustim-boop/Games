/* -------------------------------------------------------------------
   Один сценарий: открыть страницу игры, кликнуть «Рейтинг», проверить
   переход и открытый экран (заголовок содержит подпись игры). Снимки —
   только когда попросили.
   ------------------------------------------------------------------- */
async function проверитьСтраницуИгры(браузер, файл, ключ, подписьИгры, снимкиОпции) {
  console.log('\n### ' + файл + ' → рейтинг «' + ключ + '» ###');
  const контекст = await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
  const страница = await контекст.newPage();
  const красные = [];
  const заметки = [];
  следитьЗаКонсолью(страница, красные, заметки);
  await подготовитьПодделку(страница, { версия: '8.0', подпись: ПОДПИСЬ });
  await перехватить(страница, /.*/, диспетчер);

  await страница.goto(АДРЕС_СТРАНИЦ + '/' + файл, { waitUntil: 'domcontentloaded' });

  const кнопкаЕсть = (await страница.locator('#рейтинг-ссылка').count()) === 1;
  проверить(кнопкаЕсть, файл + ': на странице ровно один узел #рейтинг-ссылка');
  if (!кнопкаЕсть) {
    if (заметки.length) заметки.forEach(function (з) { сказать('заметка: ' + з); });
    проверить(красные.length === 0, файл + ': консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));
    await контекст.close();
    return;
  }

  try { await страница.locator('#рейтинг-ссылка').waitFor({ state: 'visible', timeout: 8000 }); } catch (е) { /* проверка ниже сама скажет */ }
  const видна = await страница.locator('#рейтинг-ссылка').isVisible();
  проверить(видна, файл + ': кнопка #рейтинг-ссылка видна в лобби');

  const текстКнопки = ((await страница.locator('#рейтинг-ссылка').textContent()) || '').trim();
  проверить(текстКнопки === 'Рейтинг', файл + ': текст кнопки «Рейтинг» (пришло «' + текстКнопки + '»)');

  const неПерекрыта = await страница.locator('#рейтинг-ссылка').evaluate(function (эл) {
    const прямоуг = эл.getBoundingClientRect();
    if (прямоуг.width === 0 || прямоуг.height === 0) return false;
    const х = прямоуг.left + прямоуг.width / 2;
    const у = прямоуг.top + прямоуг.height / 2;
    const верхний = document.elementFromPoint(х, у);
    return Boolean(верхний) && (верхний === эл || эл.contains(верхний));
  });
  проверить(неПерекрыта, файл + ': кнопка #рейтинг-ссылка не перекрыта другим элементом');

  if (снимкиОпции && снимкиОпции.лобби) {
    await страница.screenshot({ path: снимкиОпции.лобби });
    сказать('снимок лобби: ' + снимкиОпции.лобби);
  }

  await страница.locator('#рейтинг-ссылка').click();
  try { await страница.waitForURL(/index\.html/, { timeout: 8000 }); } catch (е) { /* адрес проверим явно ниже */ }
  await страница.waitForLoadState('domcontentloaded').catch(function () {});

  const адресТекущий = decodeURIComponent(страница.url());
  const адресВерный = адресТекущий.indexOf('index.html?рейтинг=' + ключ) !== -1;
  проверить(адресВерный, файл + ': адрес после клика содержит index.html?рейтинг=' + ключ + ' (пришло «' + адресТекущий + '»)');

  const рейтингОткрыт = await дождатьсяЭкрана(страница, 'экран-рейтинга-игроков', 8000);
  проверить(рейтингОткрыт, файл + ': на главной открылся #экран-рейтинга-игроков с классом «экран--виден»');

  if (рейтингОткрыт) {
    let текстЗаголовка = '';
    try {
      await страница.waitForFunction(function (искомое) {
        const з = document.querySelector('#экран-рейтинга-игроков .заголовок');
        return Boolean(з) && з.textContent.indexOf(искомое) !== -1;
      }, подписьИгры, { timeout: 8000 });
    } catch (е) { /* провал зафиксирует проверка ниже по факту текста */ }
    текстЗаголовка = (await страница.locator('#экран-рейтинга-игроков .заголовок').first().textContent().catch(function () { return ''; })) || '';
    проверить(текстЗаголовка.indexOf(подписьИгры) !== -1,
      файл + ': заголовок экрана рейтинга содержит «' + подписьИгры + '» (пришло «' + текстЗаголовка.trim() + '»)');
  }

  if (снимкиОпции && снимкиОпции.рейтинг) {
    await страница.screenshot({ path: снимкиОпции.рейтинг });
    сказать('снимок рейтинга: ' + снимкиОпции.рейтинг);
  }

  if (заметки.length) заметки.forEach(function (з) { сказать('заметка: ' + з); });
  проверить(красные.length === 0, файл + ': консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));

  await контекст.close();
}

