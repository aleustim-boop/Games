// С какой ширины чипы не влезают: от 400 вниз шагом 10, высота 844; партия как в (а).
async function перенос(браузер, порт, ошибки, краяЧеловеку, подпись) {
  const итог = [];
  for (let ш = 400; ш >= 300; ш -= 10) {
    const { контекст, страница } = await страницаШириной(браузер, порт, ш, 844, ошибки);
    try {
      await страница.evaluate(заводПартии, { зерно: 31, игроков: 3, краяЧеловеку: краяЧеловеку, столицаЧеловеку: true });
      await страница.waitForTimeout(900);
      const ч = await страница.evaluate(замерЧипов);
      итог.push({ ш: ш, чипов: ч.чипов, строка: ч.строка });
    } catch (е) {
      проверить('перенос чипов: обход на ' + ш + ' не упал', false, String(е.message || е).split('\n')[0]);
    }
    await контекст.close();
  }
  проверить('перенос чипов: замеры получены (ноль — провал)', итог.length === 11, 'замеров ' + итог.length);
  console.log('    [' + подпись + '] чипы по ширинам: ' + итог.map((а) => а.ш + '=' + (а.строка ? 'строка' : а.чипов + ' чип.')).join(', '));
  const первая = итог.find((а) => а.строка);
  console.log('    [' + подпись + '] ЧИПЫ НЕ ВЛЕЗАЮТ (заменяются серой строкой, на вторую строку не переносятся — nowrap) с ширины: ' + (первая ? первая.ш + ' px' : 'нет, до 300 влезают'));
}

