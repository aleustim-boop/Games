  const с = поднятьСеть('новый');
  await сесть(с);
  await с.новость(состояние(2, { спит: true }));
  const вызововДо = с.вызовыЛиста.length;
  проверить(вызововДо === 1, 'уснул: лист получил строку сна');

  const первое = с.Сеть.проснуться();
  const второе = с.Сеть.проснуться();
  const через = последнийВызов(с).двери.проснуться();
  await дождаться();
  const ходы = с.пути('/ход');
  проверить(ходы.length === 1, 'тройное нажатие, пока запрос в пути, — один запрос (' + ходы.length + ')');
  проверить(ходы.length > 0 && ходы[0].тело.действие === 'проснуться' &&
    ходы[0].тело.код === КОД && ходы[0].тело.пропуск === 'пропуск-1',
    'действие «проснуться», код и пропуск в теле');

  await с.ответНаХод(200, { принято: true, причина: null, состояние: состояние(3) });
  const [о1, о2, о3] = await Promise.all([первое, второе, через]);
  проверить(о1.принято === true && о2.принято === true && о3.принято === true && о1.причина === '',
    'все три нажатия получили один ответ — принято');
