function спросить(путь, тело, сколькоЖдать) {
  return new Promise((готово, беда) => {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, (ответ) => {
      let текст = '';
      ответ.setEncoding('utf8');
      ответ.on('data', (к) => { текст += к; });
      ответ.on('end', () => {
        let р = null;
        try { р = JSON.parse(текст); } catch (сбой) { р = { сырое: текст }; }
        готово({ код: ответ.statusCode, тело: р });
      });
    });
    запрос.setTimeout(сколькоЖдать || ЖДЁМ_КОРОТКО,
      () => запрос.destroy(new Error('сервер молчит дольше положенного')));
    запрос.on('error', беда);
    запрос.end(данные);
  });
}

const пауза = (мс) => new Promise((r) => setTimeout(r, мс));

/* ---------------------------------------------------------------------
   Как играет сам проверяющий. Ничего умного: лишь бы партия шла.
   --------------------------------------------------------------------- */

function бьёт(чем, что, козырь) {
  if (чем.масть === что.масть) return чем.вес > что.вес;
  return чем.масть === козырь && что.масть !== козырь;
}

/* Со скольких карт на столе робкий защитник перестаёт отбиваться и берёт.
   Нужно только для того, чтобы проверяемое событие случалось чаще. */
const РОБЕЮ_ОТ_КАРТ = 4;

/**
 * Перевести ход, если сервер говорит, что есть чем. Проверяющий переводит
 * при первой возможности — иначе в прогоне перевод почти не встречается,
 * а именно он и опасен: перевод меняет отбивающегося посреди подхода.
 *
 * Годится любая карта того же достоинства, что лежат на столе: остальные
 * условия перевода (сколько карт у следующего, сколько на столе) от выбора
 * карты не зависят, и сервер их уже проверил, раз сказал «могуПеревести».
 */
/**
 * Отбиваюсь ли я сейчас. В компании сервер говорит это прямо («яОтбиваюсь»),
 * а старой комнате на двоих такого поля не присылает вовсе — там это
 * выводится из «яАтакую»: за столом на двоих отбивается тот, кто не нападает.
 */
function яОтбиваюсь(вид) {
  if (вид.яОтбиваюсь !== undefined) return вид.яОтбиваюсь === true;
  return вид.яАтакую === false;
}

function решитьПеревод(вид) {
  if (!вид.могуПеревести || !яОтбиваюсь(вид) || вид.берут) return null;
  const рука = вид.мояРука || [];
  const стол = вид.стол || [];
  const достоинства = new Set();
  стол.forEach((п) => {
    if (п.атака) достоинства.add(п.атака.имя);
    if (п.защита) достоинства.add(п.защита.имя);
  });

  // Козырь на перевод тратим только тогда, когда другого нет.
  const годные = рука.map((к, i) => ({ к, i })).filter((п) => достоинства.has(п.к.имя));
  if (!годные.length) return null;
  годные.sort((а, б) => (а.к.масть === вид.козырь ? 1 : 0) - (б.к.масть === вид.козырь ? 1 : 0) ||
    а.к.вес - б.к.вес);
  return { действие: 'перевести', карта: годные[0].i };
}

function решить(вид) {
  const рука = вид.мояРука || [];
  const стол = вид.стол || [];
  const козырь = вид.козырь;

  if (яОтбиваюсь(вид) && !вид.берут) {
    // Робость: стол разросся — берём, хотя, может, и отбились бы.
    if (картНаСтоле(стол) >= РОБЕЮ_ОТ_КАРТ) return { действие: 'беру' };
    /* Вторая робость, нужная для дела: на столе две и больше неотбитых карт.
       Так выглядит стол сразу после перевода хода на меня (и после двойного
       подкидывания). Беру — и подход с переводом кончается забором карт,
       а это и есть тот случай, ради которого затевалась проверка. */
    const неотбитых = стол.filter((п) => !п.защита).length;
    if (неотбитых >= 2) return { действие: 'беру' };
    let номер = -1;
    for (let i = 0; i < стол.length; i++) { if (!стол[i].защита) { номер = i; break; } }
    if (номер < 0) return null;
    const атака = стол[номер].атака;
    const годные = рука.map((к, i) => ({ к, i }))
      .filter((п) => атака && бьёт(п.к, атака, козырь))
      .sort((а, б) => (а.к.масть === козырь ? 1 : 0) - (б.к.масть === козырь ? 1 : 0) || а.к.вес - б.к.вес);
    if (годные.length) return { действие: 'отбить', пара: номер, карта: годные[0].i };
    return { действие: 'беру' };
  }

  if (вид.яХожу) {
    if (!рука.length) return стол.length ? { действие: 'бито' } : null;
    if (!стол.length) {
      const порядок = рука.map((к, i) => ({ к, i }))
        .sort((а, б) => (а.к.масть === козырь ? 1 : 0) - (б.к.масть === козырь ? 1 : 0) || а.к.вес - б.к.вес);
      return { действие: 'ходить', карта: порядок[0].i };
    }
    const веса = new Set();
    стол.forEach((п) => { if (п.атака) веса.add(п.атака.вес); if (п.защита) веса.add(п.защита.вес); });
    const годная = рука.findIndex((к) => веса.has(к.вес) && к.масть !== козырь);
    if (годная >= 0) return { действие: 'ходить', карта: годная };
    return { действие: 'бито' };
  }
  return null;
}

/* =====================================================================
   РАЗБОР СОБЫТИЙ. Всё, что ниже, — чистый счёт по числам: эти функции
   ничего не спрашивают у сервера и потому проверяются самопроверкой
   на нарочно испорченных данных.
   ===================================================================== */

/** Сколько карт лежит на столе (и атакующих, и отбивающихся). */
function картНаСтоле(стол) {
  let счёт = 0;
  for (const пара of стол || []) {
    if (пара.атака) счёт++;
    if (пара.защита) счёт++;
  }
  return счёт;
}

/**
 * Снимок стола — всё, что нужно для разбора, и ничего лишнего.
 * Из него потом считается, куда ушли карты.
 */
function снимок(вид) {
  return {
    номер: вид.номерСобытия,
    версия: вид.версия,
    событие: вид.событие || null,
    берут: вид.берут === true,
    завершена: вид.завершена === true,
    вКолоде: вид.вКолоде || 0,
    вОтбое: вид.вОтбое || 0,
    столКарт: картНаСтоле(вид.стол),
    места: вид.застолом
      ? вид.застолом.map((м) => ({
        номер: м.номер,
        имя: м.имя,
        этоЯ: м.этоЯ === true,
        этоБот: м.этоБот === true,
        карт: м.карт || 0,
        отбивается: м.отбивается === true,
        ходит: м.ходит === true
      }))
      : местаВдвоём(вид)
  };
}

/**
 * Стол на двоих, собранный вручную.
 *
 * Старая комната на двоих списка сидящих не присылает: её ответ нарочно
 * оставлен таким, каким был до появления игры компанией. Но всё, что нужно
 * для счёта, там есть, просто россыпью:
 *   — сколько карт у меня          → длина «мояРука» (карты видно поимённо);
 *   — сколько карт у соперника     → «картУСоперника» (за столом на двоих
 *     сосед слева и есть соперник);
 *   — кто нападает                 → «яАтакую».
 *
 * Кто отбивается, отсюда следует однозначно: за столом на двоих отбивается
 * тот, кто не нападает, — других игроков в круге просто нет. Поэтому разбор
 * вдвоём получается такой же строгий, как и в компании: и прямой признак
 * («кто отбивался»), и вся арифметика карт на месте.
 *
 * Имена берём те же, какими игра называет игроков в сообщениях этой
 * комнаты: про себя она пишет «Вы», про другого — «Соперник».
 */
function местаВдвоём(вид) {
  const идётИгра = вид.завершена !== true;
  const яАтакую = вид.яАтакую === true;
  const яХожу = вид.яХожу === true;
  return [
    {
      номер: 1, имя: 'Вы', этоЯ: true, этоБот: false,
      карт: (вид.мояРука || []).length,
      отбивается: идётИгра && !яАтакую,
      ходит: идётИгра && яХожу
    },
    {
      номер: 2, имя: 'Соперник', этоЯ: false, этоБот: false,
      карт: вид.картУСоперника || 0,
      отбивается: идётИгра && яАтакую,
      ходит: идётИгра && !яХожу
    }
  ];
}

function место(снимокСтола, номер) {
  return снимокСтола.места.find((м) => м.номер === номер) || null;
}

/** Как назвать место в отчёте: «место 3 (Бот 3)». */
function какЗовут(снимокСтола, номер) {
  const м = место(снимокСтола, номер);
  return 'место ' + номер + ' (' + (м ? м.имя : 'неизвестно') + ')';
}

/**
 * Сходится ли вся картина, если предположить, что стол забрал вот этот
 * игрок. «null» значит «не забирал никто» — так бывает при «Бито».
 *
 * Считаем по правилам добора: сначала забравший берёт со стола, потом все
 * добирают из колоды до шести. Отсюда четыре условия, каждое из которых
 * нарушить нельзя:
 *   — карты у игрока не могут пропасть (стало меньше, чем было);
 *   — у кого и так было шесть и больше, добор не идёт вовсе;
 *   — добором нельзя перевалить за шесть;
 *   — пока в колоде что-то осталось, у всех должно стать ровно шесть
 *     (кроме того, у кого и так больше — он не добирает);
 *   — и, наконец, из колоды ушло ровно столько, сколько все вместе добрали.
 */
function картинаСходится(до, после, номерЗабравшего) {
  const S = до.столКарт;
  let добралиВсего = 0;

  for (const м of до.места) {
    const стало = место(после, м.номер);
    if (!стало) return false;                       // место пропало со стола — картина не та
    const было = м.карт + (м.номер === номерЗабравшего ? S : 0);
    const добор = стало.карт - было;

    if (добор < 0) return false;                    // карты не могут исчезать
    if (добор > 0 && было >= КАРТ_В_РУКЕ) return false;   // добирать было незачем
    if (добор > 0 && стало.карт > КАРТ_В_РУКЕ) return false;  // добором выше шести не поднимаются
    if (после.вКолоде > 0 && стало.карт < КАРТ_В_РУКЕ) return false;  // колода была — добрал бы
    добралиВсего += добор;
  }
  return добралиВсего === до.вКолоде - после.вКолоде;
}

/** Все, кто МОГ забрать стол по арифметике карт (обычно ровно один). */
function ктоМогЗабрать(до, после) {
  const список = [];
  for (const м of до.места) {
    if (картинаСходится(до, после, м.номер)) список.push(м.номер);
  }
  return список;
}

/**
 * Кто назван в сообщении. Возвращает номер места или null.
 *
 * Отдельно разбирается слово «Соперник». За столом на двоих игра нарочно
 * зовёт второго игрока не по имени, а «Соперником» — так эта надпись
 * выглядела с самого начала (см. ктоЭтоБыл в партия-по-сети.js). Значит,
 * вдвоём «Соперник» — это единственный, кто не я. За столом побольше
 * такого слова быть уже не должно: там у каждого есть имя.
 */
function ктоНазван(до, текст) {
  if (/^Вы\s/.test(текст)) {
    const я = до.места.find((м) => м.этоЯ);
    return я ? я.номер : null;
  }
  for (const м of до.места) {
    if (текст.indexOf(м.имя + ' ') === 0) return м.номер;
  }
  /* Запасной ход: слово «Соперник» вместо имени. Так игра говорит в СТАРОЙ
     комнате на двоих — там имён нет вовсе, и это правильно. За столом-компанией
     такого быть уже не должно, но разбирать сообщение мы всё равно умеем:
     иначе на месте одной находки («написали „Соперник" вместо имени») выросла
     бы гора бессмысленных («имя в сообщении не узнано»). За тем, каким словом
     игре положено называть игрока, следит отдельная проверка — какЗовутИгрока. */
  if (/^Соперник\s/.test(текст) && до.места.length === 2) {
    const другой = до.места.find((м) => !м.этоЯ);
    if (другой) return другой.номер;
  }
  return null;
}

/**
 * Каким словом игра называет другого игрока — и правильное ли оно для этого
 * стола. Проверка нужна ровно из-за одной путаницы:
 *
 *   — СТАРАЯ комната на двоих имён не знает вовсе, там соперник и есть
 *     «Соперник». Так было с самого начала, и менять это нельзя;
 *   — за столом-КОМПАНИЕЙ у каждого есть имя, и звать его «Соперником»
 *     нельзя даже вдвоём: игрок видит своё имя в списке за столом, а в строке
 *     событий — чужое слово.
 *
 * Возвращает жалобу строкой или null, если всё в порядке.
 */
function какЗовутИгрока(старая, снимокСтола) {
  const текст = снимокСтола.событие || '';
  if (!текст) return null;
  if (/^Вы\s/.test(текст)) return null;          // рассказ про себя — не про имена
  if (/карты розданы/i.test(текст)) return null; // общее событие, подлежащего нет

  const словомСоперник = /^Соперник\s/.test(текст);

  if (старая) {
    return словомСоперник ? null
      : 'старая комната на двоих назвала соперника не «Соперником»: «' + текст + '»';
  }
  if (словомСоперник) {
    return 'за столом-компанией игра написала «Соперник» вместо имени: «' + текст + '»';
  }
  const поИмени = снимокСтола.места.some((м) => !м.этоЯ && текст.indexOf(м.имя + ' ') === 0);
  return поИмени ? null : 'в сообщении не узнать, о ком речь: «' + текст + '»';
}

/**
 * Прибавка карт на руке. Только для отчёта: решения по ней не принимаются
 * (именно она и подводила прежнюю проверку).
 */
function прибавка(до, после, номер) {
  const а = место(до, номер);
  const б = место(после, номер);
  if (!а || !б) return 0;
  return б.карт - а.карт;
}

/**
 * Главная проверка: событие «такой-то забрал карты со стола».
 * Возвращает список жалоб (пустой — значит всё честно) и пометку,
 * удалось ли назвать забравшего однозначно по картам.
 */
function проверитьЗабор(до, после) {
  const жалобы = [];
  const S = до.столКарт;
  const названный = ктоНазван(до, после.событие);
  const отбивался = до.места.find((м) => м.отбивается);
  const кандидаты = ктоМогЗабрать(до, после);

  if (S === 0) {
    жалобы.push('сказано, что карты забрали, а на столе перед этим карт не было');
  }
  if (!до.берут) {
    жалобы.push('сказано про забор карт, хотя перед этим никто не объявлял «Беру»');
  }
  if (после.вОтбое > до.вОтбое) {
    жалобы.push('карты ушли в отбой (+' + (после.вОтбое - до.вОтбое) +
      '), значит со стола их никто не забирал');
  }

  if (названный === null) {
    жалобы.push('в сообщении названо имя, которого нет за столом: «' + после.событие + '»');
  } else {
    if (отбивался && отбивался.номер !== названный) {
      жалобы.push('названо ' + какЗовут(до, названный) + ', а отбивался ' +
        какЗовут(до, отбивался.номер) + ' — забрать стол мог только он');
    }
    const рост = прибавка(до, после, названный);
    if (рост < S) {
      жалобы.push('у названного прибавилось всего ' + рост + ' карт, а со стола ему должно ' +
        'было прийти не меньше ' + S);
    }
    if (кандидаты.length && кандидаты.indexOf(названный) === -1) {
      жалобы.push('по картам названный забрать стол не мог; сошлось только на ' +
        кандидаты.map((н) => какЗовут(до, н)).join(' или '));
    }
  }

  if (кандидаты.length === 0) {
    жалобы.push('картина не сошлась ни на ком: столько карт со стола не получил никто ' +
      '(на столе было ' + S + ', в колоде ' + до.вКолоде + ' → ' + после.вКолоде + ')');
  }

  return {
    жалобы: жалобы,
    точно: кандидаты.length === 1,
    кандидаты: кандидаты,
    названный: названный
  };
}

/**
 * Событие «перевёл ход» — самое опасное место во всей этой истории.
 * Перевод сдвигает круг: отбиваться начинает СЛЕДУЮЩИЙ игрок, а прежний
 * защитник становится нападающим. Значит, все дальнейшие сообщения
 * о заборе карт в этом подходе обязаны указывать уже на нового.
 *
 * Проверяем четыре вещи, каждая — простой счёт:
 *   — на столе стало ровно на одну карту больше;
 *   — карту потерял ровно один человек и ровно одну;
 *   — потерял её тот, кто перед этим отбивался (и он же назван в сообщении);
 *   — после перевода отбивается уже кто-то другой.
 */
function проверитьПеревод(до, после) {
  const жалобы = [];
  const переводивший = до.места.find((м) => м.отбивается);
  const названный = ктоНазван(до, после.событие);

  if (после.столКарт !== до.столКарт + 1) {
    жалобы.push('перевод кладёт на стол одну карту, а карт на столе стало ' +
      до.столКарт + ' → ' + после.столКарт);
  }

  const потеряли = [];
  const набрали = [];
  for (const м of до.места) {
    const р = прибавка(до, после, м.номер);
    if (р < 0) потеряли.push({ номер: м.номер, сколько: -р });
    if (р > 0) набрали.push({ номер: м.номер, сколько: р });
  }
  if (набрали.length) {
    жалобы.push('при переводе кому-то прибавилось карт: ' +
      набрали.map((н) => какЗовут(до, н.номер) + ' +' + н.сколько).join(', '));
  }
  if (потеряли.length !== 1 || потеряли[0].сколько !== 1) {
    жалобы.push('перевод — это одна карта из одной руки, а на самом деле ушло: ' +
      (потеряли.length ? потеряли.map((н) => какЗовут(до, н.номер) + ' −' + н.сколько).join(', ')
        : 'ни одной'));
  } else {
    if (переводивший && потеряли[0].номер !== переводивший.номер) {
      жалобы.push('карту положил ' + какЗовут(до, потеряли[0].номер) +
        ', а отбивался ' + какЗовут(до, переводивший.номер) + ' — переводить мог только он');
    }
    if (названный !== null && названный !== потеряли[0].номер) {
      жалобы.push('в сообщении назван ' + какЗовут(до, названный) +
        ', а карту при переводе положил ' + какЗовут(до, потеряли[0].номер));
    }
  }

  const новый = после.места.find((м) => м.отбивается);
  if (!после.завершена) {
    if (!новый) {
      жалобы.push('после перевода за столом никто не отбивается');
    } else if (переводивший && новый.номер === переводивший.номер) {
      жалобы.push('после перевода отбивается всё тот же ' + какЗовут(до, новый.номер) +
        ' — перевод не сдвинул круг');
    }
  }

  return { жалобы: жалобы, новый: новый ? новый.номер : null };
}

/**
 * Обратная проверка, того же рода: событие «сказал „Бито“». Тут карты
 * обязаны уйти в отбой, и ни к кому на руки они попасть не должны.
 */
function проверитьБито(до, после) {
  const жалобы = [];
  const S = до.столКарт;
  if (S === 0) {
    /* «Бито» — это про карты, которые ушли в отбой. Если на столе перед этим
       не было ни одной карты, человеку сообщают о том, чего не было. */
    жалобы.push('сказано «Бито», а на столе перед этим не было ни одной карты');
    return { жалобы: жалобы, точно: false };
  }

  if (после.вОтбое - до.вОтбое !== S) {
    жалобы.push('сказано «Бито», а в отбой ушло ' + (после.вОтбое - до.вОтбое) +
      ' карт вместо ' + S);
  }
  if (!картинаСходится(до, после, null)) {
    const кандидаты = ктоМогЗабрать(до, после);
    жалобы.push('сказано «Бито», а по картам стол ушёл кому-то на руки' +
      (кандидаты.length === 1 ? ': ' + какЗовут(до, кандидаты[0]) : ''));
  }
  return { жалобы: жалобы, точно: жалобы.length === 0 };
}

