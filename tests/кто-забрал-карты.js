/** Пустая копилка чисел — по ней складываются и разновидность, и весь прогон. */
function новаяКопилка() {
  return {
    партий: 0, событий: 0, заборов: 0, заборовТочно: 0, заборовЧужих: 0,
    объявленийБеру: 0, бито: 0, переводов: 0, заборовПослеПеревода: 0,
    битоПослеПеревода: 0, подходовЗакончилЧеловек: 0, подходовЗакончилБот: 0,
    реваншей: 0, заборовПослеРеванша: 0, зеркалоСверено: 0,
    имёнПроверено: 0, имёнНеТех: 0,
    потеряно: 0, расхождений: 0, недоигранных: 0, сорвалось: 0
  };
}

function сложить(куда, откуда) {
  for (const ключ of Object.keys(куда)) {
    if (typeof откуда[ключ] === 'number') куда[ключ] += откуда[ключ];
  }
}

/** Прогон одной разновидности игры. */
async function прогнатьРазновидность(имяРазновидности, общая) {
  const правилаСтола = РАЗНОВИДНОСТИ[имяРазновидности];
  const копилка = новаяКопилка();

  if (!правилаСтола) {
    console.log('Такой разновидности проверка не знает: «' + имяРазновидности + '». ' +
      'Возможные: ' + Object.keys(РАЗНОВИДНОСТИ).join(', ') + ', все');
    копилка.сорвалось++;
    сложить(общая, копилка);
    return копилка;
  }

  const серия = правилаСтола.подряд || 1;
  console.log('=== ' + правилаСтола.имя + ' === (комнат: ' + ПАРТИЙ +
    (серия > 1 ? ', по ' + серия + ' партии в каждой' : '') + ')');

  for (let i = 1; i <= ПАРТИЙ; i++) {
    let итог = null;
    try {
      итог = await сыгратьИПосмотреть(правилаСтола);
    } catch (сбой) {
      console.log('  Комната ' + i + ': сорвалась — ' + сбой.message);
      копилка.сорвалось++;
      continue;
    }

    копилка.партий += итог.доигранных || 0;
    копилка.событий += итог.событий;
    копилка.заборов += итог.заборов;
    копилка.заборовТочно += итог.заборовТочно;
    копилка.заборовЧужих += итог.заборовЧужих;
    копилка.объявленийБеру += итог.объявленийБеру;
    копилка.бито += итог.бито;
    копилка.переводов += итог.переводов;
    копилка.заборовПослеПеревода += итог.заборовПослеПеревода;
    копилка.битоПослеПеревода += итог.битоПослеПеревода;
    копилка.подходовЗакончилЧеловек += итог.подходовЗакончилЧеловек;
    копилка.подходовЗакончилБот += итог.подходовЗакончилБот;
    копилка.реваншей += итог.реваншей;
    копилка.заборовПослеРеванша += итог.заборовПослеРеванша;
    копилка.зеркалоСверено += итог.зеркалоСверено;
    копилка.имёнПроверено += итог.имёнПроверено;
    копилка.имёнНеТех += итог.имёнНеТех;
    копилка.потеряно += итог.потеряно;
    копилка.расхождений += итог.расхождения.length;
    if (!итог.доиграна) копилка.недоигранных++;

    console.log('  Комната ' + i + ': партий доиграно ' + итог.доигранных +
      (итог.реваншей ? ' (реваншей ' + итог.реваншей + ')' : '') +
      ', событий ' + итог.событий +
      ', заборов ' + итог.заборов + ' (однозначно по картам: ' + итог.заборовТочно + ')' +
      ', переводов ' + итог.переводов +
      ' (из них закончились забором: ' + итог.заборовПослеПеревода + ')' +
      ', «Бито» ' + итог.бито +
      ', потеряно событий ' + итог.потеряно +
      ', замечаний ' + итог.расхождения.length +
      (итог.доиграна ? '' : ', ПАРТИЯ НЕ ДОИГРАНА') +
      (итог.застоев ? ', повторных ходов из-за тишины ' + итог.застоев : ''));

    итог.расхождения.slice(0, 6).forEach((р) => {
      if (р.беда) {
        console.log('    ! ' + р.беда);
        return;
      }
      console.log('    ! событие №' + р.номерСобытия + ': «' + р.написано + '»' +
        (р.послеПеревода ? '  (в этом подходе был перевод хода!)' : ''));
      р.жалобы.forEach((ж) => console.log('        — ' + ж));
    });
    await пауза(150);
  }

  console.log('  Итого по разновидности «' + правилаСтола.имя + '»: партий ' +
    копилка.партий + ', событий ' + копилка.событий +
    ', заборов карт ' + копилка.заборов +
    ', переводов хода ' + копилка.переводов +
    ', заборов после перевода ' + копилка.заборовПослеПеревода +
    (копилка.реваншей ? ', реваншей ' + копилка.реваншей +
      ', заборов уже после реванша ' + копилка.заборовПослеРеванша : '') +
    ', подходов закончил человек ' + копилка.подходовЗакончилЧеловек +
    ' / бот ' + копилка.подходовЗакончилБот +
    (копилка.зеркалоСверено ? ', сверено сообщений с двух сторон стола ' +
      копилка.зеркалоСверено : '') +
    ', сообщений с чужим именем проверено ' + копилка.имёнПроверено +
    ' (названо не так: ' + копилка.имёнНеТех + ', ждали ' +
    (правилаСтола.старая ? '«Соперник»' : 'имя') + ')' +
    ', потеряно событий ' + копилка.потеряно +
    ', замечаний ' + копилка.расхождений + '.');
  if (правилаСтола.переводной && копилка.переводов === 0) {
    console.log('  ВНИМАНИЕ: перевод хода не случился ни разу — про переводного ' +
      'дурака этот прогон ничего не доказал.');
  }
  if (правилаСтола.подряд && копилка.реваншей === 0) {
    console.log('  ВНИМАНИЕ: реванша не случилось ни разу — про «Сыграть ещё» ' +
      'этот прогон ничего не доказал.');
  }
  console.log('');

  сложить(общая, копилка);
  return копилка;
}

