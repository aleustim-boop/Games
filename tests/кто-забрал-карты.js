/**
 * Собрать стол и сыграть в этой комнате столько партий, сколько велено
 * («подряд» — это про реванш: те же люди, та же комната, кнопка «Сыграть
 * ещё»). Возвращает копилку чисел и список замечаний.
 */
async function сыгратьИПосмотреть(правилаСтола) {
  const создатель = { имя: МОЁ_ИМЯ };

  /* Старая комната на двоих создаётся БЕЗ единой настройки: любая
     настройка превращает её в комнату-компанию, и сервер начинает
     присылать список сидящих. Нам же нужна именно старая — та,
     в которую играют живые люди с самого начала. */
  const тело = правилаСтола.старая
    ? { имя: МОЁ_ИМЯ }
    : {
      мест: правилаСтола.мест,
      переводной: правилаСтола.переводной === true,
      парами: правилаСтола.парами === true,
      имя: МОЁ_ИМЯ
    };

  const создано = await спросить('/создать', тело);
  if (создано.код !== 200 || !создано.тело.код) {
    throw new Error('сервер не дал создать комнату: ' + JSON.stringify(создано.тело));
  }
  создатель.код = создано.тело.код;
  создатель.пропуск = создано.тело.пропуск;
  создатель.вид = создано.тело.состояние;

  let друг = null;

  if (правилаСтола.второйЧеловек) {
    // За второго садится тот же скрипт — своим пропуском, как отдельный человек.
    const вход = await спросить('/войти', { код: создатель.код, имя: 'Напарник' });
    if (вход.код !== 200 || !вход.тело.пропуск) {
      throw new Error('второй игрок не вошёл: ' + JSON.stringify(вход.тело));
    }
    друг = { имя: 'Напарник', код: создатель.код, пропуск: вход.тело.пропуск, вид: вход.тело.состояние };
  }

  /* Сажаем ботов на оставшиеся места. Отказ сервера тут — уже ответ:
     значит, такой стол он не собирает, и об этом надо сказать вслух. */
  const занято = 1 + (друг ? 1 : 0);
  if (!правилаСтола.старая) {
    for (let i = занято; i < правилаСтола.мест; i++) {
      const посадка = await спросить('/ход',
        { код: создатель.код, пропуск: создатель.пропуск, действие: 'бот' });
      if (посадка.тело && посадка.тело.принято === false) {
        throw new Error('бот не сел за стол: ' + посадка.тело.причина);
      }
    }
  }

  /* Старая комната на двоих раздаёт карты сама, как только вошёл друг, —
     кнопки «Начать» там нет вовсе. Компании кнопку нажимаем. */
  let первыйВид = null;
  if (правилаСтола.старая) {
    const состояние = await спросить('/состояние',
      { код: создатель.код, пропуск: создатель.пропуск });
    первыйВид = состояние.тело && состояние.тело.состояние;
  } else {
    const начало = await спросить('/ход',
      { код: создатель.код, пропуск: создатель.пропуск, действие: 'начать' });
    if (начало.тело && начало.тело.принято === false) {
      throw new Error('партия не началась: ' + начало.тело.причина);
    }
    первыйВид = начало.тело && начало.тело.состояние;
  }
  if (!первыйВид || первыйВид.фаза === null || первыйВид.фаза === undefined) {
    throw new Error('партия не началась: ' + JSON.stringify(первыйВид));
  }
  проверитьСтол(правилаСтола, первыйВид);
  создатель.вид = первыйВид;

  /* «Партия» — всё, что знают друг о друге наши нити: та, что слушает
     события, и те, что ходят. Лента событий заполняется ТОЛЬКО из длинного
     опроса создателя — иначе события пришли бы вперемешку из разных ответов,
     и порядок сверять было бы не по чему. Ответы на свои ходы идут в «вид»:
     они нужны только чтобы решить, чем ходить дальше. */
  const партия = {
    я: создатель,
    друг: друг,
    /* Какого рода стол: старая комната на двоих (без списка сидящих и без имён)
       или комната-компания. От этого зависит, каким словом игре положено
       называть другого игрока. */
    старая: правилаСтола.старая === true,
    имёнПроверено: 0,
    имёнНеТех: 0,
    стоп: false,
    нужноПартий: правилаСтола.подряд || 1,
    крайний: Date.now() + СРОК_ПАРТИИ * (правилаСтола.подряд || 1),

    предыдущий: снимок(первыйВид),  // состояние перед последним событием
    последнийНомер: первыйВид.номерСобытия,
    когдаПоследнееСобытие: Date.now(),
    последняяЗавершённая: -1,

    событий: 0,
    потеряно: 0,
    разрывов: 0,
    заборов: 0,
    заборовТочно: 0,
    заборовЧужих: 0,
    объявленийБеру: 0,
    бито: 0,
    переводов: 0,
    былПеревод: false,          // был ли перевод в идущем сейчас подходе
    заборовПослеПеревода: 0,    // ради этого числа всё и затевалось
    битоПослеПеревода: 0,
    подходовЗакончилЧеловек: 0,
    подходовЗакончилБот: 0,
    реваншей: 0,
    заборовПослеРеванша: 0,
    доигранных: 0,
    моиСообщения: new Map(),    // номер события → как игра рассказала о нём мне
    сообщенияДруга: new Map(),  // то же самое глазами второго живого игрока
    зеркалоСверено: 0,
    расхождения: [],
    доиграна: false,
    застоев: 0
  };

  const нити = [слушать(партия), играть(партия, партия.я)];
  if (друг) {
    нити.push(слушатьМолча(партия, друг), играть(партия, друг));
  }
  await Promise.all(нити);

  сверитьБеруИЗабрал(партия);
  сверитьЗеркало(партия);

  await спросить('/выйти', { код: создатель.код, пропуск: создатель.пропуск }).catch(() => {});
  if (друг) await спросить('/выйти', { код: друг.код, пропуск: друг.пропуск }).catch(() => {});
  return партия;
}

/**
 * Сверить, что сервер собрал именно тот стол, который просили. Иначе
 * проверка «переводного» могла бы втихую пройти на обычной игре
 * и ничего не доказать.
 */
function проверитьСтол(правилаСтола, вид) {
  if (правилаСтола.старая) {
    /* Тут проверяем обратное: списка сидящих быть НЕ должно — иначе это
       уже комната-компания, и старая ветка ответа осталась непроверенной. */
    if (вид.застолом) {
      throw new Error('просили старую комнату на двоих, а сервер прислал список ' +
        'сидящих — значит, комната стала компанией, и старая ветка не проверена');
    }
    if (!вид.мояРука || вид.картУСоперника === undefined) {
      throw new Error('в ответе старой комнаты нет руки или числа карт соперника: ' +
        JSON.stringify(Object.keys(вид)));
    }
    return;
  }

  const сложилось = {
    мест: (вид.застолом || []).length,
    переводной: вид.переводной === true,
    парами: вид.парами === true
  };
  if (сложилось.мест !== правилаСтола.мест ||
      сложилось.переводной !== (правилаСтола.переводной === true) ||
      сложилось.парами !== (правилаСтола.парами === true)) {
    throw new Error('стол собрался не тот: просили мест ' + правилаСтола.мест +
      ', переводной ' + (правилаСтола.переводной === true) +
      ', парами ' + (правилаСтола.парами === true) +
      '; получилось мест ' + сложилось.мест +
      ', переводной ' + сложилось.переводной + ', парами ' + сложилось.парами);
  }
}

/**
 * Нить первая: слушаем ленту событий длинным опросом.
 *
 * Порядок действий внутри цикла выбран нарочно: получили ответ — сразу
 * отправили следующий вопрос и только после этого разбираем полученное.
 * Разбор занимает время, и если делать его до нового вопроса, в эту щель
 * может провалиться событие.
 */
async function слушать(партия) {
  let версия = партия.я.вид.версия;
  let вОжидании = спросить('/что-нового',
    { код: партия.я.код, пропуск: партия.я.пропуск, версия: версия }, ЖДЁМ_ДОЛГО);
  вОжидании.catch(() => {});

  while (!партия.стоп && Date.now() < партия.крайний) {
    let ответ = null;
    try {
      ответ = await вОжидании;
    } catch (сбой) {
      партия.расхождения.push({
        беда: 'опрос сервера оборвался: ' + сбой.message
      });
      break;
    }

    const вид = ответ && ответ.тело ? ответ.тело.состояние : null;
    if (вид && вид.версия) версия = вид.версия;

    if (ответ && ответ.тело && ответ.тело.комнатыНет) break;
    if (ответ && ответ.код !== 200) {
      партия.расхождения.push({ беда: 'сервер ответил на опрос кодом ' + ответ.код });
      break;
    }

    // Встаём в очередь за следующей новостью РАНЬШЕ, чем разбираем эту.
    if (!партия.стоп) {
      вОжидании = спросить('/что-нового',
        { код: партия.я.код, пропуск: партия.я.пропуск, версия: версия }, ЖДЁМ_ДОЛГО);
      вОжидании.catch(() => {});
    }

    if (вид) {
      партия.я.вид = вид;
      разобратьНовость(партия, вид);
      посчитатьКонецПартии(партия, вид);
    }
  }

  партия.стоп = true;
}

/**
 * Партия кончилась? Если играем серию (реванш), это ещё не конец работы:
 * ждём следующей раздачи в той же комнате. Считаем по «сыграноПартий» —
 * этот счётчик ведёт сама комната, и по нему видно каждую доигранную
 * партию, даже если мы моргнули.
 */
function посчитатьКонецПартии(партия, вид) {
  if (!вид.завершена) return;
  const сколькоСыграно = вид.сыграноПартий || (партия.доигранных + 1);
  if (сколькоСыграно === партия.последняяЗавершённая) return;

  партия.последняяЗавершённая = сколькоСыграно;
  партия.доигранных++;
  if (партия.доигранных >= партия.нужноПартий) {
    партия.доиграна = true;
    партия.стоп = true;
  }
}

/**
 * Нить второго живого игрока: он тоже держит длинный опрос, но ленту
 * событий не разбирает — она сверяется по одному источнику, иначе порядок
 * не с чем сравнивать. Его дело — знать, чем ходить, и запомнить, КАК игра
 * рассказала ему о каждом событии: потом эти рассказы сверяются с моими
 * (см. сверитьЗеркало).
 */
async function слушатьМолча(партия, игрок) {
  let версия = игрок.вид ? игрок.вид.версия : 0;

  while (!партия.стоп && Date.now() < партия.крайний) {
    let ответ = null;
    try {
      ответ = await спросить('/что-нового',
        { код: игрок.код, пропуск: игрок.пропуск, версия: версия }, ЖДЁМ_ДОЛГО);
    } catch (сбой) {
      break;
    }
    const вид = ответ && ответ.тело ? ответ.тело.состояние : null;
    if (вид) {
      версия = вид.версия;
      игрок.вид = вид;
      if (вид.событие && typeof вид.номерСобытия === 'number' &&
          !партия.сообщенияДруга.has(вид.номерСобытия)) {
        партия.сообщенияДруга.set(вид.номерСобытия, вид.событие);
      }
    }
    if (ответ && ответ.тело && ответ.тело.комнатыНет) break;
    if (ответ && ответ.код !== 200) break;
  }
}

/** Разбор одной новости: сначала непрерывность, потом — что случилось. */
function разобратьНовость(партия, вид) {
  const номер = вид.номерСобытия;
  if (typeof номер !== 'number') return;
  if (номер <= партия.последнийНомер) {
    /* Тот же номер — состояние поменялось без события (например, кто-то
       пропал со связи). Запоминаем свежий снимок и идём дальше. */
    if (номер === партия.последнийНомер) партия.предыдущий = снимок(вид);
    return;
  }

  const этот = снимок(вид);
  партия.когдаПоследнееСобытие = Date.now();

  /* Каким словом назван другой игрок: за столом-компанией — именем,
     в старой комнате на двоих — «Соперником». Эта проверка идёт РАНЬШЕ
     разбора про потерянные события нарочно: ей не нужно предыдущее
     состояние, значит и после разрыва в нумерации имя проверить можно. */
  const текстСобытия = этот.событие || '';
  if (текстСобытия && !/^Вы\s/.test(текстСобытия) && !/карты розданы/i.test(текстСобытия)) {
    партия.имёнПроверено++;
    const жалобаПроИмя = какЗовутИгрока(партия.старая, этот);
    if (жалобаПроИмя) {
      партия.имёнНеТех++;
      партия.расхождения.push({ написано: текстСобытия, номерСобытия: номер, жалобы: [жалобаПроИмя] });
    }
  }

  const скачок = номер - партия.последнийНомер;
  if (скачок > 1) {
    партия.потеряно += скачок - 1;
    партия.разрывов++;
    партия.расхождения.push({
      беда: 'ПОТЕРЯНО СОБЫТИЙ: ' + (скачок - 1) + ' (номера ' +
        (партия.последнийНомер + 1) + '…' + (номер - 1) + ' проверка не увидела). ' +
        'Событие №' + номер + ' из-за этого тоже не проверено: не с чем сравнивать'
    });
  } else {
    партия.событий++;
    const текст = этот.событие || '';
    if (текст) партия.моиСообщения.set(номер, текст);
    if (/забрал[аи]? карты со стола/i.test(текст)) {
      партия.заборов++;
      if (партия.былПеревод) партия.заборовПослеПеревода++;
      if (партия.доигранных > 0) партия.заборовПослеРеванша++;
      посчитатьКтоЗакончилПодход(партия);
      /* Считаем отдельно, когда стол забрал не проверяющий, а кто-то другой:
         про себя игра пишет «Вы забрали», и такое сообщение перепутать
         труднее. Настоящая проверка имени — как раз чужие заборы. */
      if (!/^Вы\s/.test(текст)) партия.заборовЧужих++;
      const итог = проверитьЗабор(партия.предыдущий, этот);
      if (итог.точно) партия.заборовТочно++;
      if (итог.жалобы.length) {
        партия.расхождения.push({
          написано: текст,
          номерСобытия: номер,
          послеПеревода: партия.былПеревод,
          жалобы: итог.жалобы
        });
      }
      партия.былПеревод = false;      // подход кончился
    } else if (/(Вы берёте|берёт) карты\s*$/i.test(текст)) {
      /* «Беру» объявлено. Считаем такие объявления: каждое из них обязано
         кончиться сообщением «забрал карты со стола», иначе одно сообщение
         по дороге пропало. */
      партия.объявленийБеру++;
    } else if (/(перевёл|перевели) ход/i.test(текст)) {
      партия.переводов++;
      партия.былПеревод = true;
      const итог = проверитьПеревод(партия.предыдущий, этот);
      if (итог.жалобы.length) {
        партия.расхождения.push({
          написано: текст,
          номерСобытия: номер,
          жалобы: итог.жалобы
        });
      }
    } else if (/сказал[и]? «Бито»/i.test(текст)) {
      партия.бито++;
      if (партия.былПеревод) партия.битоПослеПеревода++;
      посчитатьКтоЗакончилПодход(партия);
      const итог = проверитьБито(партия.предыдущий, этот);
      if (итог.жалобы.length) {
        партия.расхождения.push({
          написано: текст,
          номерСобытия: номер,
          послеПеревода: партия.былПеревод,
          жалобы: итог.жалобы
        });
      }
      партия.былПеревод = false;      // подход кончился
    } else if (/карты розданы/i.test(текст)) {
      партия.былПеревод = false;      // новая партия — подход начинается заново
      if (/Играем ещё раз/i.test(текст)) партия.реваншей++;
    }
  }

  партия.последнийНомер = номер;
  партия.предыдущий = этот;
}

/**
 * Кто закончил подход — живой человек или бот.
 *
 * Зачем это считать. Подход заканчивают двумя разными дорогами в коде:
 * у человека это «закончитьПодход», у бота — «ходЗаБота», и запоминают,
 * кому достанется стол, они каждая по-своему. Хочется видеть числом,
 * что прогон прошёл по обеим, а не верить на слово.
 *
 * Кто закончил — видно в состоянии ПЕРЕД событием: это тот, чей был ход
 * (он и сказал «Бито» или «больше не подкидываю»).
 */
function посчитатьКтоЗакончилПодход(партия) {
  const закончил = партия.предыдущий.места.find((м) => м.ходит);
  if (!закончил) return;
  if (закончил.этоБот) партия.подходовЗакончилБот++;
  else партия.подходовЗакончилЧеловек++;
}

/**
 * Сверка двух рассказов об одном событии — моего и второго живого игрока.
 *
 * Про себя игра пишет «Вы забрали карты со стола», про другого — «Соперник
 * забрал карты со стола». Значит, об одном и том же событии два человека
 * не могут прочитать «Вы» оба сразу: кто-то один забрал, а другой — нет.
 * Эта сверка ловит перепутанное лицо даже там, где счёт карт сошёлся.
 */
function сверитьЗеркало(партия) {
  if (!партия.друг) return;
  for (const [номер, мой] of партия.моиСообщения) {
    const чужой = партия.сообщенияДруга.get(номер);
    if (!чужой) continue;                       // друг это событие не застал
    // Общие события («карты розданы заново») одинаковы для всех — это не про лица.
    if (мой === чужой && !/^Вы\s/.test(мой)) continue;
    партия.зеркалоСверено++;

    const яПроСебя = /^Вы\s/.test(мой);
    const друг_ПроСебя = /^Вы\s/.test(чужой);
    if (яПроСебя && друг_ПроСебя) {
      партия.расхождения.push({
        беда: 'событие №' + номер + ': игра написала «про себя» ОБОИМ игрокам — ' +
          'мне «' + мой + '», второму «' + чужой + '»'
      });
    } else if (!яПроСебя && !друг_ПроСебя) {
      партия.расхождения.push({
        беда: 'событие №' + номер + ': игра написала «про другого» ОБОИМ игрокам — ' +
          'мне «' + мой + '», второму «' + чужой + '»; кто же это сделал?'
      });
    }
  }
}

/**
 * Сверка числами: сколько раз объявляли «Беру» — столько раз должно
 * прозвучать и «забрал карты со стола». Считается в конце партии.
 */
function сверитьБеруИЗабрал(партия) {
  /* Недоигранная партия тут ни при чём: её оборвали посреди подхода,
     и «Беру» без «забрал» — это не ошибка игры, а наш собственный уход.
     Потерянные события эту сверку тоже обессмысливают. */
  if (!партия.доиграна || партия.потеряно > 0) return;
  if (партия.объявленийБеру === партия.заборов) return;
  партия.расхождения.push({
    беда: 'сообщений не поровну: «Беру» объявляли ' + партия.объявленийБеру +
      ' раз, а «забрал карты со стола» прозвучало ' + партия.заборов +
      ' раз — значит, одно сообщение потерялось или появилось лишнее'
  });
}

/**
 * Нить игрока: ходим, когда очередь дошла до нас, и жмём «Сыграть ещё»,
 * когда партия кончилась, а сыграть надо ещё не одну.
 *
 * Эта же нить работает и за второго живого игрока — просто с другим
 * пропуском и своим видом стола.
 */
async function играть(партия, игрок) {
  let ходилиНа = -1;
  let когдаХодили = 0;
  let звалиНа = -1;

  while (!партия.стоп && Date.now() < партия.крайний) {
    const вид = игрок.вид;
    if (!вид) {
      await пауза(10);
      continue;
    }

    if (вид.завершена) {
      // Партия кончилась. Играем серию — зовём на реванш, иначе уходим.
      if (партия.доигранных >= партия.нужноПартий) break;
      const какая = вид.сыграноПартий || 0;
      if (звалиНа !== какая) {
        звалиНа = какая;
        await спросить('/ход',
          { код: игрок.код, пропуск: игрок.пропуск, действие: 'ещё' }).catch(() => {});
      }
      await пауза(50);
      continue;
    }

    const молчание = Date.now() - когдаХодили;
    const пораПовторить = молчание > ТИШИНА_ЭТО_ЗАСТОЙ &&
      Date.now() - партия.когдаПоследнееСобытие > ТИШИНА_ЭТО_ЗАСТОЙ;

    if (вид.яХожу && (вид.номерСобытия !== ходилиНа || пораПовторить)) {
      if (пораПовторить && вид.номерСобытия === ходилиНа) партия.застоев++;
      ходилиНа = вид.номерСобытия;
      когдаХодили = Date.now();
      await сходить(партия, игрок, вид);
      continue;
    }
    await пауза(15);
  }
}

/**
 * Сделать ход. Если сервер не принял задуманное (например, подкидывать
 * нельзя), пробуем самое безобидное — закончить подход или взять карты.
 * Отказ событием не считается и никого не будит, поэтому ждать тут нечего.
 */
async function сходить(партия, игрок, вид) {
  const попытки = [];
  // Перевод — первым делом: ради него всё и затевалось.
  const перевод = решитьПеревод(вид);
  if (перевод) попытки.push(перевод);
  const задумано = решить(вид);
  if (задумано) попытки.push(задумано);
  попытки.push({ действие: 'бито' }, { действие: 'беру' });

  for (const намерение of попытки) {
    let о = null;
    try {
      о = await спросить('/ход',
        Object.assign({ код: игрок.код, пропуск: игрок.пропуск }, намерение));
    } catch (сбой) {
      return false;
    }
    if (о.код !== 200) return false;
    if (о.тело && о.тело.состояние) игрок.вид = о.тело.состояние;
    if (о.тело && о.тело.принято) return true;
  }
  return false;
}

