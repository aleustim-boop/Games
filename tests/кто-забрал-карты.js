/* =====================================================================
   Проверка одной фразы: «такой-то забрал карты со стола».

   ЧТО ПРОВЕРЯЕМ. Когда отбивавшийся не смог отбиться, игра пишет строкой
   событий: «Бот 3 забрал карты со стола». Проверка сверяет это имя с тем,
   к кому карты со стола на самом деле ушли. Если имена расходятся —
   игра рассказывает про партию неправду.

   ---------------------------------------------------------------------
   ПОЧЕМУ ЭТУ ПРОВЕРКУ ПРИШЛОСЬ ПЕРЕПИСАТЬ

   Прежняя проверка спрашивала у сервера состояние раз в 120 мс и смотрела
   только на САМОЕ ПОСЛЕДНЕЕ событие. Боты ходят раз в 700 мс, но между
   двумя вопросами всё равно успевало пройти несколько событий, и часть
   заборов карт проверка не видела вовсе — молча. А «кто забрал на самом
   деле» она определяла по тому, у кого сильнее выросла рука. Рука растёт
   и от добора из колоды, поэтому такой признак и врал (мог назвать
   добравшего), и молчал (мог не заметить настоящего забравшего).

   Здесь обе дыры закрыты.

   1. НИ ОДНО СОБЫТИЕ НЕ ПРОСКАКИВАЕТ. Проверка не опрашивает сервер
      по часам, а висит на длинном опросе — двери «/что-нового». Сервер
      придерживает ответ, пока в комнате что-нибудь не случится, и тогда
      отвечает сразу. Следующий вопрос отправляется В ТОТ ЖЕ МИГ, как
      получен ответ, — раньше, чем разбирается сам ответ: так между двумя
      вопросами не остаётся щели, в которую могло бы провалиться событие.
      А если сервер всё-таки успел уйти вперёд (мы отстали), он отвечает
      не молчанием, а сегодняшним состоянием — и пропуск становится виден
      по номеру события.

   2. ПРОПУСК СОБЫТИЯ ВИДЕН И НАЗЫВАЕТСЯ ВСЛУХ. У каждого состояния есть
      «номерСобытия» — счётчик, который сервер увеличивает на единицу
      с каждым событием в комнате. Проверка требует, чтобы номера шли
      подряд. Скакнул номер через один — значит, событие потеряно, и это
      пишется в отчёт отдельной строкой. Молчаливых пропусков больше нет:
      именно из-за них прежнему «расхождений ноль» нельзя было верить.

   3. ЗАБОР СТОЛА ОТЛИЧАЕТСЯ ОТ ДОБОРА ИЗ КОЛОДЫ. Рост руки больше
      ни о чём сам по себе не свидетельствует. Вместо этого сверяются два
      независимых признака.

      Признак первый, прямой: в состоянии, которое было НЕПОСРЕДСТВЕННО
      перед событием (номер на единицу меньше — а это теперь гарантировано),
      видно, кто отбивался и объявлял ли он «Беру». Забрать стол может
      только он.

      Признак второй, арифметика карт. Из правил известно ровно две
      причины, по которым рука растёт в конце подхода: карты со стола
      и добор из колоды до шести. Добор при этом не произвольный: пока
      в колоде есть карты, каждый добирает РОВНО до шести и ни картой
      больше. Значит, для каждого сидящего можно прямо спросить: сходится
      ли вся картина стола (сколько у кого было, сколько стало, сколько
      ушло из колоды, сколько прибавилось в отбое), если предположить,
      что стол забрал вот он. Тех, у кого не сходится, вычёркиваем.
      Обычно остаётся один — и он обязан совпасть с названным в сообщении.
      Никакой путаницы с добором тут быть не может: добор в этой картине
      посчитан отдельно, своей строкой.

      Изредка арифметика допускает двоих (например, стол был на две карты,
      а колода полна — тогда по числам оба варианта возможны). Такие случаи
      проверка честно считает отдельно и не выдаёт за доказательство:
      там работает первый признак и жёсткое требование «у названного рука
      обязана вырасти хотя бы на число карт со стола».

   Заодно тем же способом проверяется и «Бито»: там карты обязаны уйти
   в отбой, и ни у кого не должно оказаться лишних карт на руках.

   3а. ОТДЕЛЬНО — ПЕРЕВОД ХОДА. Перевод («в переводного дурака») — это
      единственное действие в игре, которое меняет отбивающегося ПОСРЕДИ
      подхода: карта того же достоинства кладётся соседу, и отбиваться
      начинает он, а прежний защитник становится нападающим. А сервер
      запоминает, кому достанется стол, заранее — до конца подхода. Если бы
      между «запомнили» и «раздали карты» отбивающийся успевал смениться,
      игра называла бы не того. Поэтому:
        — проверяющий за столом переводит ход всегда, когда может;
        — каждое событие «перевёл ход» проверяется само по себе: одна карта
          из руки того, кто отбивался, стол вырос ровно на неё, и отбиваться
          теперь обязан уже другой;
        — считается, сколько подходов с переводом закончилось забором карт.
          Если это число ноль, прогон про переводного дурака ничего
          не доказал, и проверка говорит об этом вслух.

   4. СООБЩЕНИЕ НЕ МОЖЕТ ПРОПАСТЬ ЦЕЛИКОМ. Отдельно считается, сколько раз
      кто-нибудь объявил «Беру» и сколько раз потом прозвучало «забрал карты
      со стола». Чисел должно быть поровну: объявивший «Беру» обязательно
      заберёт стол, когда подход закончится. Разошлись — значит, одно
      сообщение потерялось по дороге, и это тоже находка.

   Ещё одна мелочь для дела: проверяющий за столом нарочно играет робко —
   когда на столе набирается четыре карты, он берёт их, даже если мог бы
   отбиться. Так проверяемое событие («такой-то забрал карты») встречается
   в несколько раз чаще, а правил игры это не нарушает: живые новички
   именно так и играют.

   Все проверки односторонние: они срабатывают только тогда, когда картина
   ЗАВЕДОМО не сходится, поэтому ложных тревог давать не должны. Что
   проверка не выдумывает своё срабатывание, показывает самопроверка
   в начале прогона — она прогоняет разбор на нарочно испорченных данных.

   ---------------------------------------------------------------------
   КАК ЗАПУСКАТЬ (сервер комнат уже поднят):

       node tests/кто-забрал-карты.js
       node tests/кто-забрал-карты.js 8825 6
       node tests/кто-забрал-карты.js 8825 3 переводной
       node tests/кто-забрал-карты.js 8825 2 все

   Первое число — порт сервера, второе — сколько партий сыграть, третье
   слово — разновидность игры:

       обычная         вчетвером, как всегда (так и будет, если не назвать);
       переводной      вчетвером, с переводом хода;
       парами          вчетвером, двое на двоих;
       парами-перевод  и то и другое разом;
       впятером        переводной на пятерых;
       вшестером       переводной на шестерых;
       все             прогнать по очереди все перечисленные.

   Скрипт сам создаёт комнату, сажает ботов и играет как обычный игрок.
   Ничего в игре не меняет — только смотрит и считает.
   ===================================================================== */

