/** Пары на столе из одного числа: столько-то карт, часть отбита. */
function поддельныйСтол(сколькоКарт) {
  const карта = { масть: '♣', имя: '6', вес: 6 };
  const стол = [];
  let осталось = сколькоКарт || 0;
  while (осталось >= 2) { стол.push({ атака: карта, защита: карта }); осталось -= 2; }
  if (осталось === 1) стол.push({ атака: карта, защита: null });
  return стол;
}

/**
 * Поддельный ответ СТАРОЙ комнаты на двоих — тот самый, в котором нет
 * списка сидящих. Нужен, чтобы прогнать разбор ровно по той дороге,
 * по которой к нему приходят настоящие ответы такой комнаты.
 */
function поддельныйВидВдвоём(настройки) {
  const карта = { масть: '♣', имя: '6', вес: 6 };
  return {
    номерСобытия: настройки.номер,
    версия: настройки.номер,
    событие: настройки.событие || null,
    берут: настройки.берут === true,
    завершена: false,
    вКолоде: настройки.вКолоде || 0,
    вОтбое: настройки.вОтбое || 0,
    мояРука: new Array(настройки.уМеня || 0).fill(карта),
    картУСоперника: настройки.уСоперника || 0,
    стол: поддельныйСтол(настройки.столКарт),
    яХожу: настройки.яХожу === true,
    яАтакую: настройки.яАтакую === true
  };
}

function поддельныйСнимок(настройки) {
  return {
    номер: настройки.номер || 1,
    версия: 1,
    событие: настройки.событие || null,
    берут: настройки.берут === true,
    завершена: false,
    вКолоде: настройки.вКолоде,
    вОтбое: настройки.вОтбое || 0,
    столКарт: настройки.столКарт || 0,
    места: настройки.места
  };
}

function самопроверка() {
  const строки = [];
  let всёХорошо = true;

  function проверить(условие, что) {
    if (!условие) всёХорошо = false;
    строки.push('   ' + (условие ? 'да ' : 'НЕТ') + '  ' + что);
  }

  /* 1. Пропуск события. Скармливаем настоящему разбору ленту с номерами
        5, 6, 8 — он обязан сказать вслух, что одно событие потеряно.
        Это проверка самого рабочего кода, а не отдельной выдумки. */
  /* Стол здесь нужен настоящий, с именами: разбор заодно проверяет, каким
     словом названы игроки, и на пустом столе честно пожаловался бы, что
     имени не узнал. Тогда проверка про пропуск события считала бы чужие
     жалобы и врала. */
  const столИзДвухБотов = [
    { номер: 1, имя: МОЁ_ИМЯ, этоЯ: true, этоБот: false, карт: 6, отбивается: false, ходит: false },
    { номер: 2, имя: 'Бот 2', этоЯ: false, этоБот: true, карт: 6, отбивается: false, ходит: true },
    { номер: 3, имя: 'Бот 3', этоЯ: false, этоБот: true, карт: 6, отбивается: false, ходит: false }
  ];
  const лента = пустаяЛента(снимок(поддельныйВид({ номер: 5, места: столИзДвухБотов })), 5);
  разобратьНовость(лента, поддельныйВид({ номер: 6, событие: 'Бот 2 походил', места: столИзДвухБотов }));
  разобратьНовость(лента, поддельныйВид({ номер: 8, событие: 'Бот 3 походил', места: столИзДвухБотов }));
  проверить(лента.потеряно === 1 && лента.расхождения.length === 1 &&
    /ПОТЕРЯНО СОБЫТИЙ: 1/.test(лента.расхождения[0].беда || ''),
    'пропуск события (номера 5, 6, 8) разбор замечает и называет вслух');
  проверить(лента.имёнПроверено === 2 && лента.имёнНеТех === 0,
    'имена в сообщениях разбор проверяет и на обычных событиях («Бот 2 походил»)');

  /* 1а. А теперь наоборот: за столом-компанией игра написала «Соперник»
         вместо имени — это ровно та беда, которую чинили. */
  const сСоперником = пустаяЛента(снимок(поддельныйВид({ номер: 1, места: столИзДвухБотов })), 1);
  разобратьНовость(сСоперником, поддельныйВид({
    номер: 2, событие: 'Соперник походил', места: столИзДвухБотов }));
  проверить(сСоперником.имёнНеТех === 1,
    'слово «Соперник» за столом-компанией разбор ловит');

  /* 1б. И обратное: в СТАРОЙ комнате на двоих «Соперник» — это правильно,
         а имя было бы ошибкой. */
  const староеНаДвоих = пустаяЛента(снимок(поддельныйВидВдвоём({ номер: 1, уМеня: 6, уСоперника: 6 })), 1);
  староеНаДвоих.старая = true;
  разобратьНовость(староеНаДвоих, поддельныйВидВдвоём({
    номер: 2, событие: 'Соперник походил', уМеня: 6, уСоперника: 6 }));
  проверить(староеНаДвоих.имёнПроверено === 1 && староеНаДвоих.имёнНеТех === 0,
    'в старой комнате на двоих слово «Соперник» разбор считает правильным');

  /* 2. Честный забор: отбивавшийся взял четыре карты со стола. */
  const доЧестного = поддельныйСнимок({
    берут: true, вКолоде: 10, вОтбое: 0, столКарт: 4,
    места: [
      { номер: 1, имя: МОЁ_ИМЯ, этоЯ: true, карт: 5, отбивается: true, ходит: false },
      { номер: 2, имя: 'Бот 2', этоЯ: false, карт: 6, отбивается: false, ходит: true }
    ]
  });
  const послеЧестного = поддельныйСнимок({
    номер: 2, событие: 'Вы забрали карты со стола', вКолоде: 10, вОтбое: 0, столКарт: 0,
    места: [
      { номер: 1, имя: МОЁ_ИМЯ, этоЯ: true, карт: 9, отбивается: false, ходит: true },
      { номер: 2, имя: 'Бот 2', этоЯ: false, карт: 6, отбивается: false, ходит: false }
    ]
  });
  const честный = проверитьЗабор(доЧестного, послеЧестного);
  проверить(честный.жалобы.length === 0 && честный.точно,
    'правильное сообщение о заборе карт разбор пропускает молча');

  /* 3. Подмена имени: карты взял первый, а названо второе место. */
  const сПодменой = Object.assign({}, послеЧестного,
    { событие: 'Бот 2 забрал карты со стола' });
  const подмена = проверитьЗабор(доЧестного, сПодменой);
  проверить(подмена.жалобы.length > 0, 'подменённое имя в сообщении разбор ловит');

  /* 3а. То же самое, но целиком по рабочему пути: от ответа сервера
         до строчки в отчёте. Так видно, что находка дойдёт до человека,
         а не потеряется где-то внутри. */
  const местаДо = [
    { номер: 1, имя: МОЁ_ИМЯ, этоЯ: true, карт: 5, отбивается: true, ходит: false },
    { номер: 2, имя: 'Бот 2', этоЯ: false, карт: 6, отбивается: false, ходит: true }
  ];
  const местаПосле = [
    { номер: 1, имя: МОЁ_ИМЯ, этоЯ: true, карт: 9, отбивается: false, ходит: true },
    { номер: 2, имя: 'Бот 2', этоЯ: false, карт: 6, отбивается: false, ходит: false }
  ];
  const двеКарты = [{ атака: {}, защита: {} }, { атака: {}, защита: {} }];
  const лживая = пустаяЛента(
    снимок(поддельныйВид({ номер: 1, берут: true, стол: двеКарты, места: местаДо })), 1);
  разобратьНовость(лживая, поддельныйВид({
    номер: 2, событие: 'Бот 2 забрал карты со стола', места: местаПосле
  }));
  проверить(лживая.заборов === 1 && лживая.расхождения.length === 1,
    'ложное сообщение о заборе доходит до отчёта целым рабочим путём');

  /* 4. Ложный сигнал старого способа: стол был на две карты, а сосед
        добрал из колоды пять — по «у кого сильнее выросла рука» назвали бы
        именно соседа. Новый разбор молчит, потому что считает добор отдельно. */
  const доСДобором = поддельныйСнимок({
    берут: true, вКолоде: 20, вОтбое: 0, столКарт: 2,
    места: [
      { номер: 1, имя: МОЁ_ИМЯ, этоЯ: true, карт: 2, отбивается: true, ходит: false },
      { номер: 2, имя: 'Бот 2', этоЯ: false, карт: 1, отбивается: false, ходит: true }
    ]
  });
  const послеСДобором = поддельныйСнимок({
    номер: 2, событие: 'Вы забрали карты со стола', вКолоде: 13, вОтбое: 0, столКарт: 0,
    места: [
      { номер: 1, имя: МОЁ_ИМЯ, этоЯ: true, карт: 6, отбивается: false, ходит: true },
      { номер: 2, имя: 'Бот 2', этоЯ: false, карт: 6, отбивается: false, ходит: false }
    ]
  });
  const сДобором = проверитьЗабор(доСДобором, послеСДобором);
  const староеМнение = прибавка(доСДобором, послеСДобором, 2) >
    прибавка(доСДобором, послеСДобором, 1);
  проверить(староеМнение && сДобором.жалобы.length === 0,
    'добор из колоды больше не путается с забором стола (прежний способ тут ошибался)');

  /* 5. «Бито», после которого карты оказались на руках. */
  const доБито = поддельныйСнимок({
    вКолоде: 0, вОтбое: 8, столКарт: 2,
    места: [
      { номер: 1, имя: МОЁ_ИМЯ, этоЯ: true, карт: 4, отбивается: true, ходит: false },
      { номер: 2, имя: 'Бот 2', этоЯ: false, карт: 3, отбивается: false, ходит: true }
    ]
  });
  const послеБито = поддельныйСнимок({
    номер: 2, событие: 'Бот 2 сказал «Бито»', вКолоде: 0, вОтбое: 8, столКарт: 0,
    места: [
      { номер: 1, имя: МОЁ_ИМЯ, этоЯ: true, карт: 6, отбивается: false, ходит: true },
      { номер: 2, имя: 'Бот 2', этоЯ: false, карт: 3, отбивается: false, ходит: false }
    ]
  });
  проверить(проверитьБито(доБито, послеБито).жалобы.length > 0,
    'ложное «Бито» (карты ушли на руки, а не в отбой) разбор ловит');

  /* 6. Перевод хода. Стол на троих: отбивался второй, перевёл ход третьему.
        Правильный перевод разбор пропускает молча. */
  const доПеревода = поддельныйСнимок({
    вКолоде: 12, вОтбое: 0, столКарт: 1,
    места: [
      { номер: 1, имя: МОЁ_ИМЯ, этоЯ: true, карт: 6, отбивается: false, ходит: false },
      { номер: 2, имя: 'Бот 2', этоЯ: false, карт: 6, отбивается: true, ходит: true },
      { номер: 3, имя: 'Бот 3', этоЯ: false, карт: 6, отбивается: false, ходит: false }
    ]
  });
  const послеПеревода = поддельныйСнимок({
    номер: 2, событие: 'Бот 2 перевёл ход', вКолоде: 12, вОтбое: 0, столКарт: 2,
    места: [
      { номер: 1, имя: МОЁ_ИМЯ, этоЯ: true, карт: 6, отбивается: false, ходит: false },
      { номер: 2, имя: 'Бот 2', этоЯ: false, карт: 5, отбивается: false, ходит: false },
      { номер: 3, имя: 'Бот 3', этоЯ: false, карт: 6, отбивается: true, ходит: true }
    ]
  });
  проверить(проверитьПеревод(доПеревода, послеПеревода).жалобы.length === 0,
    'правильный перевод хода разбор пропускает молча');

  /* 7. Перевод, после которого отбивается всё тот же человек, — так не бывает. */
  const переводБезСдвига = поддельныйСнимок({
    номер: 2, событие: 'Бот 2 перевёл ход', вКолоде: 12, вОтбое: 0, столКарт: 2,
    места: [
      { номер: 1, имя: МОЁ_ИМЯ, этоЯ: true, карт: 6, отбивается: false, ходит: false },
      { номер: 2, имя: 'Бот 2', этоЯ: false, карт: 5, отбивается: true, ходит: true },
      { номер: 3, имя: 'Бот 3', этоЯ: false, карт: 6, отбивается: false, ходит: false }
    ]
  });
  проверить(проверитьПеревод(доПеревода, переводБезСдвига).жалобы.length > 0,
    'перевод, не сдвинувший круг, разбор ловит');

  /* 8. Самое главное для переводного дурака: подход кончился забором,
        а карты приписали ПРЕЖНЕМУ отбивавшемуся — тому, кто перевёл ход
        и с тех пор уже нападает. Ровно этого мы и боимся в правке, где
        отбивающийся запоминается заранее. */
  const доЗабораПослеПеревода = поддельныйСнимок({
    берут: true, вКолоде: 0, вОтбое: 6, столКарт: 2,
    места: [
      { номер: 1, имя: МОЁ_ИМЯ, этоЯ: true, карт: 4, отбивается: false, ходит: true },
      { номер: 2, имя: 'Бот 2', этоЯ: false, карт: 5, отбивается: false, ходит: false },
      { номер: 3, имя: 'Бот 3', этоЯ: false, карт: 5, отбивается: true, ходит: false }
    ]
  });
  const послеЗабораПослеПеревода = поддельныйСнимок({
    номер: 2, вКолоде: 0, вОтбое: 6, столКарт: 0,
    места: [
      { номер: 1, имя: МОЁ_ИМЯ, этоЯ: true, карт: 4, отбивается: false, ходит: false },
      { номер: 2, имя: 'Бот 2', этоЯ: false, карт: 5, отбивается: false, ходит: false },
      { номер: 3, имя: 'Бот 3', этоЯ: false, карт: 7, отбивается: false, ходит: true }
    ]
  });
  const честноеПослеПеревода = Object.assign({}, послеЗабораПослеПеревода,
    { событие: 'Бот 3 забрал карты со стола' });
  const ложноеПослеПеревода = Object.assign({}, послеЗабораПослеПеревода,
    { событие: 'Бот 2 забрал карты со стола' });
  проверить(проверитьЗабор(доЗабораПослеПеревода, честноеПослеПеревода).жалобы.length === 0,
    'после перевода правильное имя забравшего разбор пропускает молча');
  проверить(проверитьЗабор(доЗабораПослеПеревода, ложноеПослеПеревода).жалобы.length > 0,
    'после перевода забор, приписанный прежнему отбивавшемуся, разбор ловит');

  /* 9. Старая комната на двоих. Списка сидящих сервер не присылает, стол
        собирается из руки, числа карт соперника и того, кто нападает.
        Гоняем разбор прямо на таком ответе — как он приходит с сервера. */
  const доВдвоём = снимок(поддельныйВидВдвоём({
    номер: 5, событие: 'Соперник берёт карты', берут: true,
    вКолоде: 0, вОтбое: 10, уМеня: 4, уСоперника: 3, столКарт: 4,
    яХожу: true, яАтакую: true
  }));
  const послеВдвоёмЧестно = снимок(поддельныйВидВдвоём({
    номер: 6, событие: 'Соперник забрал карты со стола',
    вКолоде: 0, вОтбое: 10, уМеня: 4, уСоперника: 7, столКарт: 0,
    яХожу: false, яАтакую: false
  }));
  const послеВдвоёмЛожно = Object.assign({}, послеВдвоёмЧестно,
    { событие: 'Вы забрали карты со стола' });
  проверить(доВдвоём.места.length === 2 && доВдвоём.места[1].отбивается === true &&
    доВдвоём.места[0].карт === 4 && доВдвоём.места[1].карт === 3,
    'стол на двоих собирается из ответа старой комнаты (без списка сидящих)');
  проверить(проверитьЗабор(доВдвоём, послеВдвоёмЧестно).жалобы.length === 0,
    'вдвоём правильное сообщение о заборе разбор пропускает молча');
  проверить(проверитьЗабор(доВдвоём, послеВдвоёмЛожно).жалобы.length > 0,
    'вдвоём забор, приписанный не тому, разбор ловит');

  /* 9а. Стол на двоих, собранный компанией: у мест есть имена, но игра
         всё равно зовёт второго «Соперником». Разбор обязан понимать,
         что «Соперник» вдвоём — это тот, кто не я. */
  const доИменного = поддельныйСнимок({
    берут: true, вКолоде: 0, вОтбое: 6, столКарт: 2,
    места: [
      { номер: 1, имя: МОЁ_ИМЯ, этоЯ: true, карт: 4, отбивается: false, ходит: true },
      { номер: 2, имя: 'Напарник', этоЯ: false, карт: 5, отбивается: true, ходит: false }
    ]
  });
  const послеИменного = поддельныйСнимок({
    номер: 2, событие: 'Соперник забрал карты со стола', вКолоде: 0, вОтбое: 6, столКарт: 0,
    места: [
      { номер: 1, имя: МОЁ_ИМЯ, этоЯ: true, карт: 4, отбивается: false, ходит: false },
      { номер: 2, имя: 'Напарник', этоЯ: false, карт: 7, отбивается: false, ходит: true }
    ]
  });
  проверить(проверитьЗабор(доИменного, послеИменного).жалобы.length === 0,
    'вдвоём слово «Соперник» разбор понимает как «тот, кто не я»');

  /* 10. Зеркало: об одном событии оба игрока не могут прочитать «Вы». */
  const зеркало = {
    друг: {}, зеркалоСверено: 0, расхождения: [],
    моиСообщения: new Map([[7, 'Вы забрали карты со стола']]),
    сообщенияДруга: new Map([[7, 'Вы забрали карты со стола']])
  };
  сверитьЗеркало(зеркало);
  проверить(зеркало.расхождения.length === 1,
    'если обоим написали «Вы забрали карты», разбор это ловит');

  console.log('Самопроверка разбора (на выдуманных данных, игру не трогаем):');
  строки.forEach((с) => console.log(с));
  console.log(всёХорошо
    ? '   Итог: разбор ловит подлог и не поднимает ложную тревогу.'
    : '   Итог: САМ РАЗБОР НЕИСПРАВЕН — результатам прогона верить нельзя!');
  console.log('');
  return всёХорошо;
}

