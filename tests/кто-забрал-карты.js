    старая: false,
    имёнПроверено: 0,
    имёнНеТех: 0,
    когдаПоследнееСобытие: 0,
    доигранных: 0,
    событий: 0, потеряно: 0, разрывов: 0,
    заборов: 0, заборовТочно: 0, заборовЧужих: 0, объявленийБеру: 0, бито: 0,
    переводов: 0, былПеревод: false, заборовПослеПеревода: 0, битоПослеПеревода: 0,
    подходовЗакончилЧеловек: 0, подходовЗакончилБот: 0,
    реваншей: 0, заборовПослеРеванша: 0,
    моиСообщения: new Map(),
