'use strict';

/* Проверка без браузера: лобби и итог партии морского боя сделаны как у дурака
   и шашек (владелец 02.10: «все онлайн игры в одном стиле, эталон — дурак»).
   Читает разметку и код как текст.

   Запуск:  node tests/морской-бой-как-дурак.js [морской-бой.html] [морской-бой-экран.js] [style-морской-бой.css]
   Пути нужны для «красного» запуска: проверка на КОПИЯХ, где поломку вернули
   (нет места, нет «В меню», нет строки рейтинга…), обязана упасть. Настоящие
   файлы портить нельзя.

   Ноль найденных узлов — провал, а не пропуск: каждая проверка сначала
   требует, чтобы нужный узел нашёлся. */

const fs = require('fs');
const path = require('path');

const корень = path.join(__dirname, '..');
function путь(номер, обычный) {
  return process.argv[номер] ? path.resolve(process.argv[номер]) : path.join(корень, обычный);
}
const путьHtml = путь(2, 'морской-бой.html');
const html = fs.readFileSync(путьHtml, 'utf8');
const экран = fs.readFileSync(путь(3, 'js/морской-бой-экран.js'), 'utf8');
const стили = fs.readFileSync(путь(4, 'style-морской-бой.css'), 'utf8');

let провалов = 0;
let всего = 0;
function проверить(условие, слова) {
  всего++;
  if (!условие) провалов++;
  console.log((условие ? '  ок      ' : '  ПРОВАЛ  ') + слова);
}

/** Кусок текста от начала до конца (включительно); пусто, если не нашли. */
function кусок(текст, начало, конец) {
  const от = текст.indexOf(начало);
  if (от === -1) return '';
  const до = текст.indexOf(конец, от);
  return до === -1 ? '' : текст.slice(от, до + конец.length);
}

console.log('Страница: ' + путьHtml);

// 1. Каркас лобби — общие классы, не «фото-лобби».
console.log('\n1. Каркас лобби');
const лобби = кусок(html, '<section id="экран-лобби"', '</section>');
проверить(лобби.length > 0, 'секция «экран-лобби» найдена');
проверить(!/фото-лобби/.test(лобби), 'классов «фото-лобби*» в лобби нет');
проверить(/<h1 class="лобби__заголовок">Морской бой<\/h1>/.test(лобби), 'заголовок h1.лобби__заголовок');
проверить(/<div class="лобби__входы">/.test(лобби), 'входы в div.лобби__входы');

// 2. Карточка профиля — место в рейтинге.
console.log('\n2. Карточка профиля');
const профиль = кусок(лобби, '<button id="лобби-профиль"', '</button>');
проверить(профиль.length > 0 && /class="карточка-профиля"/.test(профиль), 'карточка «лобби-профиль» с классом карточка-профиля');
проверить(/id="лобби-аватар" class="аватар"/.test(профиль), 'аватар «лобби-аватар»');
проверить(/id="лобби-рейтинг"[^>]*карточка-профиля__рейтинг--нет/.test(профиль), 'строка «лобби-рейтинг» с классом --нет');
проверить(/id="лобби-место"/.test(профиль), 'узел «лобби-место» на месте');
проверить(!/Мой профиль и результаты/.test(профиль), 'старой подписи вместо места нет');
проверить(/ЭкранРейтинга\?*\.моёМесто\('морской-бой'\)/.test(экран), 'место берётся ЭкранРейтинга.моёМесто(\'морской-бой\')');
проверить(/карточка-профиля__рейтинг--нет/.test(экран), 'код ставит/снимает класс --нет по наличию места');

// 3. Картинка с подписью.
console.log('\n3. Картинка-гнездо');
const картинка = кусок(лобби, '<figure', '</figure>');
проверить(/class="лобби__картинка"/.test(картинка), 'figure.лобби__картинка найдена');
const подпись = /<figcaption class="лобби__подпись">([^<]+)<\/figcaption>/.exec(картинка);
проверить(Boolean(подпись) && подпись[1].trim().length > 0, 'есть подпись figcaption.лобби__подпись' + (подпись ? ' («' + подпись[1].trim() + '»)' : ''));
проверить(/class="лобби__рисунок"/.test(картинка), 'картинка с классом лобби__рисунок');
проверить(стили.length > 0 && !/\.море-афиша/.test(стили), 'старой рамки «.море-афиша» в style-морской-бой.css нет');

// 4. Карточки входов и нижняя полоса.
console.log('\n4. Карточки входов');
const онлайн = кусок(лобби, '<button id="лобби-найти-игру"', '</button>');
проверить(/карточка-входа__название">Играть онлайн</.test(онлайн), 'карточка «Играть онлайн»');
const боты = кусок(лобби, '<button id="море-боты"', '</button>');
проверить(/карточка-входа__название">Играть с ботами</.test(боты), 'карточка «Играть с ботами»');
const правила = кусок(лобби, '<button id="лобби-правила"', '</button>');
проверить(/карточка-входа__название">Как играть</.test(правила), '«Как играть» есть в лобби (до партии)');
проверить(/<nav class="нижние-вкладки"/.test(лобби), 'нижняя полоса «нижние-вкладки» в лобби');

// 5. Итог партии (окно, набор и порядок — как у шашек).
console.log('\n5. Итог партии');
const итог = кусок(html, '<dialog id="море-результат"', '</dialog>');
проверить(итог.length > 0, 'окно «море-результат» найдено');
const порядок = [];
for (const [id, слово, главная] of [
  ['кнопка-ещё', 'Играть ещё', true], ['кнопка-реванш', 'Реванш', true], ['кнопка-ещё-с-ботом', 'Сыграть с ботом', true],
  ['кнопка-похвастаться', 'Похвастаться', false], ['кнопка-рекорды-итог', 'Рекорды', false], ['кнопка-в-меню-итог', 'В меню', false]
]) {
  const кнопка = кусок(итог, '<button id="' + id + '"', '</button>');
  проверить(кнопка.length > 0 && кнопка.indexOf('>' + слово + '<') !== -1, 'на итоге есть «' + слово + '» (id ' + id + ')');
  проверить(кнопка.length > 0 && /кнопка--главная/.test(кнопка) === главная, '  класс «' + слово + '»: ' + (главная ? 'главная' : 'мелкая') + ', как у шашек');
  порядок.push(итог.indexOf('<button id="' + id + '"'));
}
проверить(порядок.every((n, i) => n > -1 && (i === 0 || n > порядок[i - 1])), 'порядок кнопок: Играть ещё, Реванш, Сыграть с ботом, Похвастаться, Рекорды, В меню');
проверить(!/class="[^"]*скрыт[^"]*"[^>]*>В меню</.test(кусок(итог, '<button id="кнопка-в-меню-итог"', '</button>')), '«В меню» не спрятана в разметке');
проверить(/<p id="итог-рейтинга" class="подпись скрыт">/.test(итог), 'строка «итог-рейтинга» на месте');
проверить(/<p id="подпись-реванша" class="подпись скрыт">/.test(итог), 'подпись реванша на месте');
проверить(!/id="море-реванш"|id="море-в-лобби"/.test(html), 'старых «море-реванш» и «море-в-лобби» в разметке нет');
проверить(/ОчкиРейтинга\.словаИтога\(/.test(экран), 'строка рейтинга пишется через ОчкиРейтинга.словаИтога');
проверить(/\$\('кнопка-реванш'\)\.onclick/.test(экран), '«Реванш» привязан к клику в js/морской-бой-экран.js');
проверить(/\$\('кнопка-в-меню-итог'\)\.onclick/.test(экран), '«В меню» привязана в js/морской-бой-экран.js');
проверить(/\$\('кнопка-ещё-с-ботом'\)\.onclick/.test(экран), '«Сыграть с ботом» привязана');
проверить(/\$\('кнопка-рекорды-итог'\)\.onclick/.test(экран), '«Рекорды» привязаны');
проверить(/Сеть\.похвастаться\(описание\)/.test(экран) && /игра: 'морской-бой'/.test(экран), '«Похвастаться» идёт общей дорогой Сеть.похвастаться');

// 6. Подключения.
console.log('\n6. Подключения');
проверить(/<script src="js\/очки-рейтинга\.js/.test(html), 'js/очки-рейтинга.js подключён');

console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
process.exit(провалов === 0 ? 0 : 1);
