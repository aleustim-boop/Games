'use strict';

/* Проверка: «раздачаДня» и «ходов» ложатся в журнал партий и выходят наружу,
   обычная партия не растёт ни на знак, счётчики не тронуты. Плюс замер места
   в худшем случае: журнал полон (40 ботовых + 60 живых), и все партии — раздачи дня. */

/* Поддельный браузер — общий (tests/поддельный-браузер.js): память и часы,
   которые переставляют рукой. Своей копии здесь нет. */
const браузер = require('./поддельный-браузер.js');

const беды = [];
let проверок = 0;
function проверить(условие, что) { проверок++; if (!условие) { беды.push(что); console.log('  ПЛОХО: ' + что); } else { console.log('  ок: ' + что); } }

const часы = браузер.поддельныеЧасы(new Date(2026, 8, 7, 12, 0).getTime());
const ДЕНЬ = 86400000;
const номерДня = (г, м, д) => Math.floor((Date.UTC(г, м - 1, д) - Date.UTC(2020, 0, 1)) / ДЕНЬ);
const поставитьЧасы = (г, м, д) => часы.поставить(г, м, д, 12, 0);

const сделатьПамять = () => браузер.сделатьПамять(false);

function завести(память) {
  const х = браузер.поднятьTelegramJS({ память, часы });
  return { Р: х.Рейтинг, память };
}

const журнал = (память) => JSON.parse(память.ящик.rating_durak).партии;
const последняя = (память) => JSON.stringify(журнал(память)[журнал(память).length - 1]);
const байтов = (т) => Buffer.byteLength(т, 'utf8');

(async () => {
  const СЕГОДНЯ = номерДня(2026, 9, 7);
  поставитьЧасы(2026, 9, 7);

  console.log('=== 1. Обычная партия не выросла ни на знак ===');
  {
    const х = завести(сделатьПамять());
    await х.Р.записатьПартию({ исход: 'победа', подпись: 'сложный', раздачаДня: '', ходов: 0 });
    const з = последняя(х.память);
    console.log('  запись: ' + з);
    проверить(з === `[${СЕГОДНЯ},1,2,0,3]`, 'обычная партия с ботом — пять чисел, как и раньше');
    await х.Р.записатьПартию({ исход: 'поражение', подпись: 'обычный', соперники: 'люди', кто: 'id42' });
    проверить(последняя(х.память) === `[${СЕГОДНЯ},0,2,1,0,"id42"]`, 'живая партия — шесть мест, как и раньше');
    await х.Р.записатьПартию({ исход: 'победа', подпись: 'обычный' });
    проверить(последняя(х.память) === `[${СЕГОДНЯ},1,2,0,2]`, 'описание без новых полей вовсе — по-старому');
  }

  console.log('=== 2. Раздача дня и ходы ложатся в журнал и выходят наружу ===');
  {
    const х = завести(сделатьПамять());
    const РАЗДАЧА = номерДня(2026, 9, 6);
    await х.Р.записатьПартию({ исход: 'победа', подпись: 'сложный', раздачаДня: '2026-09-06', ходов: 37 });
    const з = последняя(х.память);
    console.log('  ботовая раздача дня: ' + з + '  (+' + (з.length - `[${СЕГОДНЯ},1,2,0,3]`.length) + ' знаков)');
    проверить(з === `[${СЕГОДНЯ},1,2,0,3,0,37,${РАЗДАЧА}]`, 'в журнале: ноль вместо «кто», ходы, номер дня раздачи');
    await х.Р.записатьПартию({ исход: 'ничья', подпись: 'обычный', соперники: 'люди', кто: 'id42', раздачаДня: '2026-09-07', ходов: 120 });
    const ж = последняя(х.память);
    console.log('  живая раздача дня:   ' + ж);
    проверить(ж === `[${СЕГОДНЯ},2,2,1,0,"id42",120,${СЕГОДНЯ}]`, 'у живой партии «кто» строкой, дальше ходы и раздача');
    await х.Р.записатьПартию({ исход: 'победа', подпись: 'лёгкий', ходов: 9 });
    проверить(последняя(х.память) === `[${СЕГОДНЯ},1,2,0,1,0,9]`, 'ходы без раздачи — хвост короче на одно место');

    const с = await х.Р.прочитать('дурак');
    const п = с.последниеПартии;   // свежие сверху
    console.log('  наружу: ' + p(п[2]) + ' | ' + p(п[1]) + ' | ' + p(п[0]));
    проверить(п[2].раздачаДня === '2026-09-06' && п[2].ходов === 37 && п[2].кто === '', 'первая: раздача 2026-09-06, 37 ходов, «кто» пусто');
    проверить(п[1].раздачаДня === '2026-09-07' && п[1].ходов === 120 && п[1].кто === 'id42', 'вторая: раздача 2026-09-07, 120 ходов, кто id42');
    проверить(п[0].раздачаДня === '' && п[0].ходов === 9, 'третья: раздачи нет, 9 ходов');
    // По уровням — две строки: у живой партии уровня нет (правило файла), клеток — три
    проверить(с.всего.партий === 3 && с.поУровням.length === 2 && с.подробно.length === 3, 'счётчики и клетки — как у обычных партий, разреза «раздача» нет');
    проверить(JSON.stringify(с).indexOf('раздача') < 0 || JSON.stringify(с.поУровням).indexOf('раздача') < 0, 'в разрезах слова «раздача» нет');
  }
  function p(п) { return п.раздачаДня + '/' + п.ходов + '/' + (п.кто || '-'); }

  console.log('=== 3. Мусор в новых полях — партия обычная ===');
  {
    const х = завести(сделатьПамять());
    for (const раздача of ['2026-13-45', '2026-02-30', 'abc', 42, null, '07.09.2026', '2019-12-31', ' 2026-09-07 ']) {
      await х.Р.записатьПартию({ исход: 'победа', подпись: 'обычный', раздачаДня: раздача, ходов: 0 });
      const з = последняя(х.память);
      const ждём = раздача === ' 2026-09-07 ' ? `[${СЕГОДНЯ},1,2,0,2,0,0,${СЕГОДНЯ}]` : `[${СЕГОДНЯ},1,2,0,2]`;
      проверить(з === ждём, 'раздачаДня = ' + JSON.stringify(раздача) + ' → ' + з);
    }
    await х.Р.записатьПартию({ исход: 'победа', подпись: 'обычный', ходов: -5 });
    проверить(последняя(х.память) === `[${СЕГОДНЯ},1,2,0,2]`, 'ходов −5 — как ноль');
    await х.Р.записатьПартию({ исход: 'победа', подпись: 'обычный', ходов: 1e9 });
    проверить(последняя(х.память) === `[${СЕГОДНЯ},1,2,0,2,0,9999]`, 'ходов миллиард — обрезано до 9999');
    await х.Р.записатьПартию({ исход: 'победа', подпись: 'обычный', ходов: '41' });
    проверить(последняя(х.память) === `[${СЕГОДНЯ},1,2,0,2,0,41]`, 'ходов строкой «41» — понято как 41');
  }

  console.log('=== 4. Записи переживают перечитывание; старые виды читаются ===');
  {
    const память = сделатьПамять();
    const старое = {
      версия: 1, игра: 'дурак', всего: [4, 4, 0, 0], серия: [0, 0], клетки: {}, серии: {}, начало: '', обновлено: '',
      партии: [
        [2400, 1, 2, 'старый-ид'],                 // самый старый вид: [день, исход, стол, кто]
        [2401, 1, 2, 0, 2],                        // обычная
        [2402, 1, 2, 1, 0, 'id7'],                 // живая без хвоста
        [2403, 1, 2, 0, 2, 0, 37, 2403],           // раздача дня
        [2404, 1, 2, 0, 2, 'мусор-вместо-нуля', 'x', -1]   // порча в хвосте
      ]
    };
    память.setItem('rating_durak', JSON.stringify(старое));
    const х = завести(память);
    const с = await х.Р.прочитать('дурак');
    const п = с.последниеПартии;
    проверить(п.length === 5, 'все пять записей прочитаны');
    проверить(п[4].кто === 'старый-ид' && п[4].соперники === 'люди' && п[4].ходов === 0 && п[4].раздачаДня === '', 'самый старый вид: живая, без ходов и раздачи');
    проверить(п[1].ходов === 37 && п[1].раздачаДня === '2026-07-31', 'раздача дня из журнала: номер 2403 → 2026-07-31');
    проверить(п[0].кто === 'мусор-вместо-нуля' && п[0].ходов === 0 && п[0].раздачаДня === '', 'порча в хвосте — строка стала «кто», остальное нули');
    await х.Р.записатьПартию({ исход: 'победа', подпись: 'обычный' });
    const ж = журнал(память);
    проверить(JSON.stringify(ж[3]) === '[2403,1,2,0,2,0,37,2403]', 'после перезаписи раздача дня в журнале цела');
    проверить(JSON.stringify(ж[4]) === '[2404,1,2,0,2,"мусор-вместо-нуля"]', 'порченый хвост при перезаписи ужат до «кто»');
  }

  console.log('=== 5. Замер места: журнал полон ===');
  {
    /* кому: 'никому' — раздач нет; 'ботам' — раздача дня у всех 40 ботовых партий
       (жизненный случай: раздачу дня играют с ботом); 'всем' — и у 60 живых тоже (край). */
    async function наполнить(кому) {
      const х = завести(сделатьПамять());
      let день = 1;
      for (let i = 0; i < 100; i++) {
        поставитьЧасы(2026, 1 + Math.floor(день / 28), 1 + (день % 28)); день++;
        const живая = i % 5 !== 0;
        const описание = {
          исход: ['победа', 'поражение', 'ничья'][i % 3],
          подпись: ['лёгкий', 'обычный', 'сложный'][i % 3] + (i % 2 ? ' · вшестером' : ''),
          игроков: 2 + (i % 5),
          парами: i % 7 === 0
        };
        if (живая) { описание.соперники = 'люди'; описание.кто = '1234567' + (100 + i); }
        if (кому === 'всем' || (кому === 'ботам' && !живая)) {
          описание.раздачаДня = '2026-0' + (1 + Math.floor(день / 28)) + '-' + String(1 + (день % 28)).padStart(2, '0');
          описание.ходов = 40 + i;   // двузначные и трёхзначные ходы вперемешку
        }
        await х.Р.записатьПартию(описание);
      }
      // добиваем ботовые до 40 — все с ботом, значит все с раздачей, если она есть
      for (let i = 0; i < 40; i++) {
        поставитьЧасы(2026, 6, 1 + (i % 28));
        const описание = { исход: 'победа', подпись: 'сложный · вшестером', игроков: 6 };
        if (кому !== 'никому') { описание.раздачаДня = '2026-06-' + String(1 + (i % 28)).padStart(2, '0'); описание.ходов = 55 + i; }
        await х.Р.записатьПартию(описание);
      }
      const текст = х.память.ящик.rating_durak;
      const з = JSON.parse(текст);
      const живых = з.партии.filter(п => п[3] === 1).length;
      return { знаков: текст.length, байтов: байтов(текст), партий: з.партии.length, живых, ботовых: з.партии.length - живых, клеток: Object.keys(з.клетки).length };
    }
    const без = await наполнить('никому');
    const ботам = await наполнить('ботам');
    const всем = await наполнить('всем');
    const строкой = (р) => р.знаков + ' знаков, ' + р.байтов + ' байтов; в журнале ' + р.партий + ' партий (' + р.живых + ' живых, ' + р.ботовых + ' ботовых)';
    console.log('  без раздач:                    ' + строкой(без) + ', клеток ' + без.клеток);
    console.log('  раздачи у 40 ботовых (жизнь):  ' + строкой(ботам) + '  → +' + (ботам.знаков - без.знаков) + ' знаков, по ' + ((ботам.знаков - без.знаков) / 40).toFixed(1) + ' на раздачу');
    console.log('  раздачи у всех 100 (край):     ' + строкой(всем) + '  → +' + (всем.знаков - без.знаков) + ' знаков');
    проверить(ботам.знаков <= 3500 && ботам.байтов <= 4000, 'жизненный случай — в прежнем пределе (3500 знаков / 4000 байтов)');
    проверить(ботам.партий === без.партий, 'жизненный случай — ни одна партия из журнала не вылетела');
    проверить(всем.знаков <= 3500 && всем.байтов <= 4000, 'край — текст всё равно в пределе (подрезка сработала)');
    проверить(всем.живых === 60 && всем.ботовых >= 20, 'край — живые партии целы (60), ботовых не меньше двадцати');
  }

  console.log('\nпроверок сделано: ' + проверок);
  if (беды.length) { console.log('=== ИТОГ: ЕСТЬ БЕДЫ (' + беды.length + ') ==='); беды.forEach(б => console.log('  - ' + б)); process.exit(1); }
  console.log('=== ИТОГ: раздача дня и ходы лежат в журнале, место в пределе ===');
})();
