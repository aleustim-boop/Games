'use strict';

/* Постоянная проверка партии 5 рейтинга: поддельный браузер,
   четыре сценария (полный список с порциями, новичок, беда связи,
   шторка выбора игры — план «Шторка выбора игры», раздел tests/).
   Ломающие запуски: --ломить-порцию и --ломить-имена (сценарии 1-3),
   --сломать-шторку (сценарий 4 — портит КОПИЮ исходника в памяти:
   заголовок шторки, галочку активного пункта, фокус после закрытия). */

const fs = require('fs');
const path = require('path');
const бр = require(path.join(__dirname, 'поддельный-браузер.js'));

const КОРЕНЬ = path.join(__dirname, '..');
const FILE_ARG = process.argv.find(функция => функция.startsWith('--файл='));
const файлРейтинга = FILE_ARG ? FILE_ARG.split('=')[1] : path.join(КОРЕНЬ, 'js', 'рейтинг-экран.js');
const исходник = fs.readFileSync(файлРейтинга, 'utf8');

/* Ломающий запуск сценария 4: портит КОПИЮ исходника ТОЛЬКО в памяти
   (файл проекта не трогаем) — меняет текст заголовка шторки, имя класса
   галочки активного пункта и убирает возврат фокуса на кнопку выбора
   игры при закрытии. Используется только сценарием 4 ниже. */
const СЛОМАТЬ_ШТОРКУ = process.argv.indexOf('--сломать-шторку') !== -1;
let исходникШторки = исходник;
if (СЛОМАТЬ_ШТОРКУ) {
  const ЗАГОЛОВОК_ИСКОМОЕ = "заголовокПанели.textContent = 'Выбрать игру';";
  const ГАЛОЧКА_ИСКОМОЕ = "галочка.className = 'рейтинг-панель-игр__галочка';";
  const ФОКУС_ИСКОМОЕ = "if (кнопкаВыбора && typeof кнопкаВыбора.focus === 'function') кнопкаВыбора.focus();";
  if (исходник.indexOf(ЗАГОЛОВОК_ИСКОМОЕ) === -1 || исходник.indexOf(ГАЛОЧКА_ИСКОМОЕ) === -1 || исходник.indexOf(ФОКУС_ИСКОМОЕ) === -1) {
    console.log('ОШИБКА: приём порчи --сломать-шторку устарел (устройство изменилось) — не нашлись искомые строки в ' + файлРейтинга);
    process.exit(1);
  }
  исходникШторки = исходник
    .split(ЗАГОЛОВОК_ИСКОМОЕ).join("заголовокПанели.textContent = 'Игры';")
    .split(ГАЛОЧКА_ИСКОМОЕ).join("галочка.className = 'рейтинг-панель-игр__НЕТ-галочки';")
    .split(ФОКУС_ИСКОМОЕ).join('/* порчено --сломать-шторку: фокус на кнопку выбора игры убран */');
  console.log('Ломающий запуск --сломать-шторку: порчу КОПИЮ в памяти —');
  console.log('  заголовок шторки на «Игры», класс галочки на несуществующий, фокус на закрытии убран.');
  console.log('');
}

let провалов = 0;
let всегоПроверок = 0;

function проверить(имя, годно) {
  всегоПроверок += 1;
  console.log((годно ? '  ok  ' : ' ПЛОХО ') + имя);
  if (!годно) провалов += 1;
}

function ждать(мс) { return new Promise(function (r) { setTimeout(r, мс || 40); }); }

function игрок(место, имя, очки, этоЯ) {
  return { место: место, имя: имя, очки: очки, побед: место, партий: место + 5, этоЯ: !!этоЯ };
}

const верхушка = [];
for (let м = 1; м <= 25; м++) верхушка.push(игрок(м, 'Игрок Номер' + м, 30000 - м * 100));
const вокругМеня = [];
for (let м = 33; м <= 43; м++) вокругМеня.push(игрок(м, 'Сосед Снизу' + м, 24900 - м, м === 38));

const ответУспех = {
  узналиВас: true, всего: 120, яВТаблице: true,
  я: игрок(38, 'Алексей Петров', 24860, true),
  верхушка: верхушка, вокругМеня: вокругМеня
};

function fetchОтвет(данные) {
  return function () {
    return Promise.resolve({ json: function () { return Promise.resolve(данные); } });
  };
}

function строкиСписка(таблица) {
  const все = Array.prototype.slice.call(таблица.querySelectorAll('.рейтинг-строка'));
  return все.filter(function (с) {
    return !с.classList.contains('рейтинг-строка--шапка') &&
           !с.classList.contains('рейтинг-строка--разрыв');
  });
}

async function прогон() {
  /* ---- Сценарий 1: полный список, порции по 10 ---- */
  const поднятый = бр.поднять(исходник, { имяФайла: 'js/рейтинг-экран.js', fetch: fetchОтвет(ответУспех) });
  поднятый.окно.ЭкранРейтинга.открыть('дурак');
  await ждать();
  поднятый.документ.getElementById('кнопка-рейтинг-очки').click();
  const таблица = поднятый.документ.getElementById('рейтинг-таблица');

  let строки = строкиСписка(таблица);
  const своиСтроки = строки.filter(function (с) { return с.classList.contains('рейтинг-строка--я'); });
  проверить('первая порция: 10 строк списка плюс карточка «моё место» = 11', строки.length === 11);
  проверить('список начинается с 4-го места', строки[0] && строки[0].getAttribute('data-место') === '4');
  проверить('десятая строка списка — 13-е место', строки[9] && строки[9].getAttribute('data-место') === '13');
  проверить('карточка «моё место» внизу — моё 38-е место', строки[10] && строки[10].getAttribute('data-место') === '38');
  проверить('своя строка помечена классом --я ровно один раз', своиСтроки.length === 1);
  проверить('кнопка «Показать ещё» есть', Boolean(поднятый.документ.getElementById('кнопка-рейтинг-показать-ещё')));
  проверить('обёртка .рейтинг-список-конец есть', Boolean(таблица.querySelector('.рейтинг-список-конец')));
  проверить('разрыва пока нет (места идут подряд)', !таблица.querySelector('.рейтинг-строка--разрыв'));

  const очкиПервой = строки[0].querySelector('.рейтинг-очки');
  проверить('очки с неразрывным пробелом тысяч: «' + очкиПервой.textContent + '»',
    очкиПервой.textContent.indexOf(' ') !== -1);
  const инициалыПервой = строки[0].querySelector('.рейтинг-аватар__инициалы');
  проверить('инициалы в строке: «ИН» для «Игрок Номер4»',
    Boolean(инициалыПервой) && инициалыПервой.textContent === 'ИН');
  const инициалыПодиума = таблица.querySelector('.рейтинг-подиум-аватар').querySelector('.рейтинг-аватар__инициалы');
  проверить('инициалы внутри аватара подиума есть', Boolean(инициалыПодиума));

  /* «Показать ещё» три раза — список у клиента кончается */
  поднятый.документ.getElementById('кнопка-рейтинг-показать-ещё').click();
  строки = строкиСписка(таблица);
  проверить('после первого «Показать ещё» строк списка стало 20 (+карточка)', строки.length === 21);

  поднятый.документ.getElementById('кнопка-рейтинг-показать-ещё').click();
  поднятый.документ.getElementById('кнопка-рейтинг-показать-ещё').click();
  строки = строкиСписка(таблица);
  проверить('после трёх нажатий показаны все 33 строки клиента', строки.length === 33);
  проверить('разрыв 25 → 33 нарисован', Boolean(таблица.querySelector('.рейтинг-строка--разрыв')));
  проверить('кнопки «Показать ещё» больше нет',
    !поднятый.документ.getElementById('кнопка-рейтинг-показать-ещё'));
  const итогСписка = таблица.querySelector('.рейтинг-список-конец__итог');
  проверить('подпись конца списка: «' + (итогСписка && итогСписка.textContent) + '»',
    Boolean(итогСписка) && итогСписка.textContent.indexOf('Показаны первые') === 0);
  const свои = строки.filter(function (с) { return с.classList.contains('рейтинг-строка--я'); });
  проверить('своя строка показана ровно один раз (карточка внизу ушла)', свои.length === 1);
  проверить('ошибок в консоли нет', поднятый.ошибкиКонсоли.length === 0);

  /* Значок выбранной игры */
  const кнопкаИгры = поднятый.документ.getElementById('рейтинг-выбор-игры-кнопка');
  const значок = кнопкаИгры.querySelector('.рейтинг-выбор-игры__значок');
  проверить('на кнопке выбора игры есть значок', Boolean(значок));
  проверить('значок ведёт на img/рейтинг/дурак.png', Boolean(значок) && значок.src === 'img/рейтинг/дурак.png');
  проверить('у значка есть srcset на 2x', Boolean(значок) && значок.srcset.indexOf('@2x.png 2x') !== -1);
  проверить('подпись кнопки осталась «Дурак»', кнопкаИгры.textContent.indexOf('Дурак') !== -1);

  /* ---- Сценарий 2: меня в таблице нет — карточка новичка ---- */
  const ответНовичка = { узналиВас: true, всего: 120, яВТаблице: false, верхушка: верхушка, вокругМеня: [] };
  const поднятый2 = бр.поднять(исходник, { имяФайла: 'js/рейтинг-экран.js', fetch: fetchОтвет(ответНовичка) });
  поднятый2.окно.ЭкранРейтинга.открыть('дурак');
  await ждать();
  поднятый2.документ.getElementById('кнопка-рейтинг-очки').click();
  const таблица2 = поднятый2.документ.getElementById('рейтинг-таблица');
  const новичок = таблица2.querySelector('.рейтинг-строка--новичок');
  проверить('карточка новичка есть', Boolean(новичок));
  проверить('у карточки новичка класс --я', Boolean(новичок) && новичок.classList.contains('рейтинг-строка--я'));
  const подсказка = новичок && новичок.querySelector('.рейтинг-новичок-подсказка');
  проверить('подсказка «Сыграйте первую рейтинговую партию»',
    Boolean(подсказка) && подсказка.textContent === 'Сыграйте первую рейтинговую партию');
  проверить('место новичка — «—»',
    Boolean(новичок) && новичок.querySelector('.рейтинг-место').textContent === '—');
  проверить('очки новичка — 0',
    Boolean(новичок) && новичок.querySelector('.рейтинг-очки').textContent === '0');
  проверить('инициалов у новичка нет (имени нет)', Boolean(новичок) && !новичок.querySelector('.рейтинг-аватар__инициалы'));
  проверить('ошибок в консоли нет (новичок)', поднятый2.ошибкиКонсоли.length === 0);

  /* ---- Сценарий 3: беда связи — кнопка «Повторить» ---- */
  let походов = 0;
  const fetchБеда = function () { походов += 1; return Promise.reject(new Error('поддельная беда связи')); };
  const поднятый3 = бр.поднять(исходник, { имяФайла: 'js/рейтинг-экран.js', fetch: fetchБеда });
  поднятый3.окно.ЭкранРейтинга.открыть('дурак');
  await ждать();
  поднятый3.документ.getElementById('кнопка-рейтинг-очки').click();
  const кнопкаПовтор = поднятый3.документ.getElementById('кнопка-рейтинг-повторить');
  проверить('при беде связи есть кнопка «Повторить»', Boolean(кнопкаПовтор));
  проверить('у кнопки «Повторить» класс кнопка--тихая',
    Boolean(кнопкаПовтор) && кнопкаПовтор.classList.contains('кнопка--тихая'));
  const былоПоходов = походов;
  if (кнопкаПовтор) кнопкаПовтор.click();
  await ждать();
  проверить('нажатие «Повторить» идёт на сервер заново (' + былоПоходов + ' → ' + походов + ')',
    походов > былоПоходов);
  проверить('ошибок в консоли нет (беда связи)', поднятый3.ошибкиКонсоли.length === 0);

  /* ---- Сценарий 4: шторка выбора игры (план «Шторка выбора игры») ---- */
  const поднятый4 = бр.поднять(исходникШторки, { имяФайла: 'js/рейтинг-экран.js', fetch: fetchОтвет(ответУспех) });
  поднятый4.окно.ЭкранРейтинга.открыть('дурак');
  await ждать();

  const кнопкаВыбораШторки = поднятый4.документ.getElementById('рейтинг-выбор-игры-кнопка');
  проверить('кнопка выбора игры на месте (открывает шторку)', Boolean(кнопкаВыбораШторки));

  const заголовокШторки = поднятый4.документ.querySelector('.рейтинг-панель-игр__заголовок');
  проверить('заголовок шторки — узел h2.рейтинг-панель-игр__заголовок',
    Boolean(заголовокШторки) && заголовокШторки.tagName === 'H2');
  проверить('текст заголовка шторки — «Выбрать игру» (сейчас «' + (заголовокШторки && заголовокШторки.textContent) + '»)',
    Boolean(заголовокШторки) && заголовокШторки.textContent === 'Выбрать игру');

  /* Поддельный DOM не ведёт document.activeElement — ловим сам вызов
     focus() подменой метода на узле (узел один и тот же при повторных
     getElementById, подмена переживает между кликами). */
  let фокусовВПоле = 0;
  const полеПоискаШторки = поднятый4.документ.getElementById('рейтинг-панель-игр-поиск');
  if (полеПоискаШторки) полеПоискаШторки.focus = function () { фокусовВПоле += 1; };
  let фокусовНаКнопке = 0;
  if (кнопкаВыбораШторки) кнопкаВыбораШторки.focus = function () { фокусовНаКнопке += 1; };

  if (кнопкаВыбораШторки) кнопкаВыбораШторки.click();
  await ждать();

  const панельШторки = поднятый4.документ.getElementById('рейтинг-панель-игр');
  проверить('клик по кнопке выбора игры открывает шторку (класс «скрыт» снят)',
    Boolean(панельШторки) && !панельШторки.classList.contains('скрыт'));
  проверить('указатель точный (поддельный matchMedia matches:false) → фокус позван в поле поиска',
    фокусовВПоле > 0);

  const списокШторки = поднятый4.документ.getElementById('рейтинг-панель-игр-список');
  const разделыШторки = списокШторки ? списокШторки.querySelectorAll('.рейтинг-панель-игр__раздел') : [];
  проверить('раздел «ИГРЫ» нашёлся в шторке (настоящий реестр, без поиска)',
    Array.prototype.some.call(разделыШторки, function (р) { return р.textContent === 'ИГРЫ'; }));
  проверить('раздела «СКОРО» на настоящем реестре нет (выдуманных игр в сборнике нет)',
    !Array.prototype.some.call(разделыШторки, function (р) { return р.textContent === 'СКОРО'; }));

  const галочкиШторки = списокШторки ? списокШторки.querySelectorAll('.рейтинг-панель-игр__галочка') : [];
  проверить('галочка «✓» стоит ровно у одного пункта шторки (сейчас: ' + галочкиШторки.length + ')',
    галочкиШторки.length === 1);
  const пунктДуракаШторки = поднятый4.документ.getElementById('рейтинг-панель-игр-пункт-дурак');
  проверить('галочка стоит именно у активного пункта «Дурак» (открыт рейтинг дурака)',
    Boolean(пунктДуракаШторки) && Boolean(пунктДуракаШторки.querySelector('.рейтинг-панель-игр__галочка')));

  const кнопкаЗакрытьШторку = поднятый4.документ.getElementById('рейтинг-панель-игр-закрыть');
  if (кнопкаЗакрытьШторку) кнопкаЗакрытьШторку.click();
  проверить('после закрытия шторки фокус позван на кнопку #рейтинг-выбор-игры-кнопка',
    фокусовНаКнопке > 0);

  /* Указатель «грубый» (палец, matchMedia pointer:coarse) — фокус в поле
     поиска звать НЕЛЬЗЯ (план, риск 2: клавиатура не выезжает сама). */
  поднятый4.окно.matchMedia = function () {
    return { matches: true, addEventListener: function () {}, addListener: function () {} };
  };
  фокусовВПоле = 0;
  if (кнопкаВыбораШторки) кнопкаВыбораШторки.click();
  await ждать();
  проверить('указатель грубый (палец) → фокус в поле поиска НЕ позван', фокусовВПоле === 0);

  проверить('ошибок в консоли нет (шторка выбора игры)', поднятый4.ошибкиКонсоли.length === 0);

  console.log('');
  console.log('Итого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
  if (провалов) process.exit(1);
}

прогон().catch(function (ошибка) {
  console.error('Ошибка прогона:', ошибка);
  process.exit(1);
});
