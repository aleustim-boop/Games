// Проверка раскладки (правило владельца 09.10): у каждой игры своя папка игры/<игра>/.
// Запуск: node tests/у-каждой-игры-своя-папка.js [--корень=путь]
// Без браузера: читает html-страницы корня и файлы папок, ничего не меняет.
const fs = require('fs');
const path = require('path');

let корень = path.join(__dirname, '..');
for (const довод of process.argv.slice(2)) {
  if (довод.startsWith('--корень=')) корень = довод.substring('--корень='.length);
}

// ДОЛГ — нарушения, которые были на 09.10. Список можно только СОКРАЩАТЬ.
// Форма записи: 'пункт: путь' — как в сообщении о провале. Причина — в комментарии.
// Запись, которая перестала быть нарушением, — тоже провал («вычеркни из долга»).
const ДОЛГ = new Set([
  // Витринные стили катана и монополии лежат в папках игр, но ни одна страница их не подключает
  // (на 09.10 их упоминает только tests/монополия-публикация.js): подключить или удалить.
  'г: игры/катан/style-катан-витрина.css',
  'г: игры/монополия/style-монополия-витрина.css',
  // Общие файлы, которые на деле просит одна страница: перенести в папку этой игры
  // или подключить второй игре.
  'д: общее/js/вход-со-страниц.js',  // просит только index.html (дурак)
  'д: общее/js/деберц-онлайн.js',    // просит только катан.html (деберц.html его не подключает)
  'д: общее/js/турнир-экран.js',     // просит только index.html (дурак)
  'д: общее/css/style-витрина.css',  // просит только index.html (дурак)
]);

const РАЗРЕШЁННЫЕ_ПАПКИ_ОБЩЕГО = new Set(['js', 'css', 'casual', 'шрифты']);
const РАСШИРЕНИЯ_ИГРЫ = new Set(['.css', '.js']);
// Папки, куда не заглядываем, когда ищем, кто просит файл (чужие данные, секреты, зависимости)
const ПРОПУСК = new Set(['node_modules', 'данные', 'nginx', '.git']);

const нарушения = new Map(); // ключ -> пояснение
let проверок = 0;
function нарушение(пункт, путь, пояснение) {
  нарушения.set(`${пункт}: ${путь}`, пояснение);
}
function проверка() { проверок++; }

function список(папка) {
  try { return fs.readdirSync(папка, { withFileTypes: true }); } catch (e) { return []; }
}
function читать(путь) {
  try { return fs.readFileSync(путь, 'utf8'); } catch (e) { return ''; }
}
// Все js-файлы папки (рекурсивно), без чужих данных и секретов; .env не читаем вообще
function jsВПапке(папка, итог = []) {
  for (const э of список(папка)) {
    if (ПРОПУСК.has(э.name) || э.name.startsWith('.')) continue;
    const п = path.join(папка, э.name);
    if (э.isDirectory()) jsВПапке(п, итог);
    else if (э.name.endsWith('.js')) итог.push(п);
  }
  return итог;
}
// Имя файла встречается в тексте как отдельное слово (кириллица: \b не годится)
function упоминается(текст, имя) {
  const буква = /[\p{L}\p{N}_-]/u;
  let от = 0;
  for (;;) {
    const и = текст.indexOf(имя, от);
    if (и < 0) return false;
    const до = и > 0 ? текст[и - 1] : ' ';
    const после = текст[и + имя.length] || ' ';
    if (!буква.test(до) && !буква.test(после)) return true;
    от = и + 1;
  }
}

// ---------- страницы ----------
const страницы = список(корень).filter(э => э.isFile() && э.name.endsWith('.html')).map(э => э.name);
проверка();
if (страницы.length === 0) нарушение('а', 'корень', 'не найдено ни одной страницы — проверка слепа');
const папкаСтраницы = имя => {
  const б = имя.replace(/\.html$/, '');
  return б === 'index' ? 'дурак' : б;
};

// Подключения страницы: [{ путь, тег }], только css/js из игры/ и общее/
function подключения(имяСтраницы) {
  const текст = читать(path.join(корень, имяСтраницы));
  const итог = [];
  const рег = /<(script|link)\b[^>]*?(?:src|href)\s*=\s*["']([^"']+)["'][^>]*>/gi;
  let м;
  while ((м = рег.exec(текст))) {
    if (м[1].toLowerCase() === 'link' && !/rel\s*=\s*["']stylesheet["']/i.test(м[0])) continue;
    let п = м[2].split('#')[0].split('?')[0];
    if (/^[a-z]+:/i.test(п)) continue;
    п = п.replace(/^\.?\//, '');
    try { п = decodeURIComponent(п); } catch (e) { /* оставляем как есть */ }
    if (п.startsWith('игры/') || п.startsWith('общее/')) итог.push(п);
  }
  return итог;
}

const подключенияСтраниц = {};
for (const с of страницы) {
  проверка();
  подключенияСтраниц[с] = подключения(с);
  if (подключенияСтраниц[с].length === 0) {
    нарушение('в', с, 'страница не подключает ни одного файла из игры/ или общее/ — проверка слепа');
  }
}

// ---------- папки игр ----------
const папкиИгр = list => list;
const игрыДир = path.join(корень, 'игры');
const названияПапок = список(игрыДир).filter(э => э.isDirectory()).map(э => э.name);
проверка();
if (названияПапок.length === 0) нарушение('а', 'игры/', 'не найдено ни одной папки игры — проверка слепа');

// а) страница <-> папка
for (const с of страницы) {
  проверка();
  const п = папкаСтраницы(с);
  if (!названияПапок.includes(п)) нарушение('а', с, `у страницы нет папки игры «игры/${п}»`);
}
const именаСтраниц = new Set(страницы.map(папкаСтраницы));
for (const п of названияПапок) {
  проверка();
  if (!именаСтраниц.has(п)) нарушение('а', `игры/${п}`, 'у папки игры нет страницы в корне');
}

// б) в папке игры только файлы css/js; а) папка не пустая
const файлыИгр = {}; // папка -> [имена]
for (const п of названияПапок) {
  const вся = список(path.join(игрыДир, п));
  файлыИгр[п] = [];
  проверка();
  if (вся.length === 0) нарушение('а', `игры/${п}`, 'папка игры пустая');
  for (const э of вся) {
    проверка();
    if (э.isDirectory()) { нарушение('б', `игры/${п}/${э.name}`, 'в папке игры лежит подпапка'); continue; }
    if (!РАСШИРЕНИЯ_ИГРЫ.has(path.extname(э.name).toLowerCase())) {
      нарушение('б', `игры/${п}/${э.name}`, 'в папке игры чужое расширение (разрешены css и js)');
      continue;
    }
    файлыИгр[п].push(э.name);
  }
}

// в) страница просит из игры/ только свою папку
for (const с of страницы) {
  const своя = папкаСтраницы(с);
  for (const п of подключенияСтраниц[с]) {
    проверка();
    if (п.startsWith('игры/') && п.split('/')[1] !== своя) {
      нарушение('в', `${с} -> ${п}`, `страница просит файл из чужой папки игры (своя — игры/${своя})`);
    }
  }
}

// ---------- кто о ком упоминает ----------
const серверИБот = [...jsВПапке(path.join(корень, 'server')), ...jsВПапке(path.join(корень, 'bot'))];
const текстыСервераИБота = серверИБот.map(читать);
const текстыОбщего = {}; // путь -> текст для js/css общего
function файлыОбщего(вид) {
  return список(path.join(корень, 'общее', вид)).filter(э => э.isFile()).map(э => э.name);
}
for (const вид of ['js', 'css']) {
  for (const и of файлыОбщего(вид)) текстыОбщего[`общее/${вид}/${и}`] = читать(path.join(корень, 'общее', вид, и));
}
const текстыИгр = {}; // путь -> текст
for (const п of названияПапок) {
  for (const и of файлыИгр[п]) текстыИгр[`игры/${п}/${и}`] = читать(path.join(игрыДир, п, и));
}
const упомянутСервером = имя => текстыСервераИБота.some(т => упоминается(т, имя));

// г) каждый файл игры кому-то нужен
for (const п of названияПапок) {
  const своиСтраницы = страницы.filter(с => папкаСтраницы(с) === п);
  const просятСтраницы = new Set();
  for (const с of своиСтраницы) for (const х of подключенияСтраниц[с]) просятСтраницы.add(х);
  for (const и of файлыИгр[п]) {
    проверка();
    const путь = `игры/${п}/${и}`;
    if (просятСтраницы.has(путь)) continue;
    const другойВТойЖеПапке = файлыИгр[п].some(д => д !== и && упоминается(текстыИгр[`игры/${п}/${д}`], и));
    if (другойВТойЖеПапке) continue;
    if (упомянутСервером(и)) continue;
    нарушение('г', путь, 'никому не нужен: ни своя страница, ни файл той же папки, ни сервер/бот его не просят');
  }
}

// д) файлы общего просят минимум две страницы
const просящихСтраниц = путь => страницы.filter(с => подключенияСтраниц[с].includes(путь));
for (const путь of Object.keys(текстыОбщего)) {
  проверка();
  const имя = path.basename(путь);
  const кто = просящихСтраниц(путь);
  if (кто.length >= 2) continue;
  if (кто.length === 1) {
    нарушение('д', путь, `просит одна страница (${кто[0]}) — ему место в папке этой игры`);
    continue;
  }
  // Никто не просит тегом: смотрим, не подгружается ли из другого файла или сервером
  const изДругогоФайла = [...Object.keys(текстыОбщего), ...Object.keys(текстыИгр)]
    .some(д => д !== путь && упоминается(текстыОбщего[д] ?? текстыИгр[д], имя));
  if (изДругогоФайла || упомянутСервером(имя)) continue;
  нарушение('д', путь, 'не просит ни одна страница, не подгружается ни другим файлом, ни сервером/ботом');
}

// е) в общее/ только разрешённые папки
проверка();
const общееДир = path.join(корень, 'общее');
if (список(общееДир).length === 0) нарушение('е', 'общее/', 'папка общее/ не найдена или пуста — проверка слепа');
for (const э of список(общееДир)) {
  проверка();
  if (э.isDirectory() && !РАЗРЕШЁННЫЕ_ПАПКИ_ОБЩЕГО.has(э.name)) {
    нарушение('е', `общее/${э.name}`, 'лишняя папка в общее/ (разрешены js, css, casual, шрифты)');
  }
}

// ---------- сверка с долгом ----------
const провалы = [];
for (const [ключ, пояснение] of нарушения) {
  if (!ДОЛГ.has(ключ)) провалы.push(`  ${ключ} — ${пояснение}`);
}
for (const ключ of ДОЛГ) {
  проверка();
  if (!нарушения.has(ключ)) провалы.push(`  ${ключ} — вычеркни из долга: это уже не нарушение`);
}

console.log(`Итого проверок: ${проверок}, провалов: ${провалы.length}`);
console.log(`Страниц: ${страницы.length}, папок игр: ${названияПапок.length}, в долгу: ${ДОЛГ.size}`);
if (провалы.length > 0) {
  console.log('\nНарушения:');
  console.log(провалы.join('\n'));
  console.log('\nПодсказка: файл игры — в игры/<игра>/, общий (нужен двум играм и больше) — в общее/.');
  process.exit(1);
}
