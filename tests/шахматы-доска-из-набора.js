const fs = require('fs');
const path = require('path');
const { chromium, подготовитьПодделку } = require('./браузер-робот.js');

const КОРЕНЬ = path.resolve(path.join(__dirname, '..'));
const ПОРТ = Number(process.argv[2]) || 8080;
const СЛОМАТЬ = process.argv.includes('--сломать');
const АДРЕС = 'http://127.0.0.1:' + ПОРТ + '/' + encodeURIComponent('шахматы.html');
const ПАПКА_СНИМКОВ = path.join(__dirname, 'снимки');

let всегоПроверок = 0;
let провалов = 0;
function проверить(условие, слова) {
  всегоПроверок++;
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}
const спать = (мс) => new Promise((ф) => setTimeout(ф, мс));

/* ==================================================================
   ЧАСТЬ 1 — БЕЗ БРАУЗЕРА: файлы набора на диске, разметка в html.
   ================================================================== */
function частьБезБраузера() {
  console.log('=== Без браузера: файлы набора и разметка ===');

  const путьCSS = path.join(КОРЕНЬ, 'style-шахматы.css');
  const css = fs.readFileSync(путьCSS, 'utf8');
  // Пути url(...) читаем ИЗ САМОГО css — переписанный руками список
  // однажды разойдётся с настоящим (кто-то добавит картинку и забудет
  // проверку). url() в этом файле — только относительные пути набора,
  // без data: и без http(s):.
  const пути = [...css.matchAll(/url\(\s*['"]?([^'")]+)['"]?\s*\)/g)].map((м) => м[1]);
  проверить(пути.length >= 15, 'в style-шахматы.css есть url(...) набора: ' + пути.length);
  console.log('  путей в css: ' + пути.length);
  for (const путь of пути) {
    const полный = path.join(КОРЕНЬ, путь.split('?')[0]);
    проверить(fs.existsSync(полный), 'файл набора на месте: ' + путь);
  }

  const html = fs.readFileSync(path.join(КОРЕНЬ, 'шахматы.html'), 'utf8');
  проверить(!/шахматы-доска-вид\.js/.test(html),
    'в шахматы.html нет подключения js/шахматы-доска-вид.js');
  проверить(!/id=["']экран-оформления["']/.test(html),
    'в шахматы.html нет id="экран-оформления"');
  проверить(!fs.existsSync(path.join(КОРЕНЬ, 'js', 'шахматы-доска-вид.js')),
    'файла js/шахматы-доска-вид.js на диске больше нет');
}

/* ==================================================================
   ЧАСТЬ 2 — БРАУЗЕР.
   ================================================================== */
async function новая(браузер, ш, в) {
  const окно = await браузер.newContext({ viewport: { width: ш, height: в }, hasTouch: true, deviceScaleFactor: 2 });
  const страница = await окно.newPage();
  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
    красные.push('консоль: ' + м.text());
  });
  await подготовитьПодделку(страница, { версия: '8.0', полныйЭкран: 'дают' });
  await страница.goto(АДРЕС);
  await спать(400);
  return { окно, страница, красные };
}

async function тапПоПолю(страница, поле) {
  await страница.evaluate((имя) => {
    const узел = document.querySelector('[data-поле="' + имя + '"]');
    if (узел) узел.click();
  }, поле);
}

/** Общие проверки вида доски: фигуры, подписи, буквы снизу. Одинаковы
 *  для обоих размеров экрана — доска рисуется тем же кодом. */
async function проверитьОбщийВидДоски(страница, подпись) {
  const данные = await страница.evaluate(() => {
    const фигуры = [...document.querySelectorAll('#доска .фигура')];
    const разбор = фигуры.map((ф) => ({
      текст: (ф.textContent || '').trim(),
      классы: [...ф.classList]
    }));
    const метокВРамке = document.querySelectorAll('.доска-шахмат-рамка > .метка-буква, .доска-шахмат-рамка > .метка-цифра').length;
    const метокВКлетках = document.querySelectorAll('.поле .метка-буква, .поле .метка-цифра').length;
    const буквы = [...document.querySelectorAll('.метка-буква')]
      .sort((а, б) => а.getBoundingClientRect().left - б.getBoundingClientRect().left)
      .map((у) => у.textContent.trim());
    return { всего: разбор.length, разбор: разбор, метокВРамке: метокВРамке, метокВКлетках: метокВКлетках, буквы: буквы };
  });

  проверить(данные.всего === 32, подпись + ': на доске 32 узла .фигура, вышло ' + данные.всего);
  const безТекста = данные.разбор.every((ф) => ф.текст === '');
  проверить(безТекста, подпись + ': ни у одной фигуры нет текста (знака)');
  const уКаждойПараКлассов = данные.разбор.every((ф) => {
    const цвет = ф.классы.filter((к) => /^фигура--(белая|чёрная)$/.test(к));
    const вид = ф.классы.filter((к) => /^фигура--(король|ферзь|ладья|слон|конь|пешка)$/.test(к));
    return ф.классы.length === 3 && цвет.length === 1 && вид.length === 1;
  });
  проверить(уКаждойПараКлассов, подпись + ': у каждой фигуры ровно два класса — цвет и вид');

  проверить(данные.метокВРамке === 16, подпись + ': меток в рамке 16, вышло ' + данные.метокВРамке);
  проверить(данные.метокВКлетках === 0, подпись + ': меток внутри клеток 0, вышло ' + данные.метокВКлетках);
  проверить(данные.буквы.join('') === 'abcdefgh',
    подпись + ': буквы снизу слева направо a…h, вышло «' + данные.буквы.join('') + '»');

  return данные;
}

(async () => {
  console.log('Доска шахмат из набора владельца. Страница: ' + АДРЕС);

  частьБезБраузера();

  const браузер = await chromium.launch();

  /* ----------------------------------------------------------------
     390×844 — основной размер: вид доски, снимок, ход e2–e4, конь b1.
     ---------------------------------------------------------------- */
  console.log('\n=== 390×844: вид доски (старт) ===');
  {
    const { окно, страница, красные } = await новая(браузер, 390, 844);
    await страница.click('#лобби-вдвоём');
    await спать(600);

    if (СЛОМАТЬ) {
      // Ломаем ровно так, как просили: у одной фигуры снимаем класс
      // вида (остаётся только цвет — пара классов пропадает), и прячем
      // три подписи поля, будто их не нарисовали.
      await страница.evaluate(() => {
        const ф = document.querySelector('#доска .фигура');
        if (ф) {
          const видКласс = [...ф.classList].find((к) => /^фигура--(король|ферзь|ладья|слон|конь|пешка)$/.test(к));
          if (видКласс) ф.classList.remove(видКласс);
        }
        [...document.querySelectorAll('.метка-буква, .метка-цифра')].slice(0, 3).forEach((у) => у.remove());
      });
      console.log('  --сломать: у одной фигуры снят класс вида, три подписи поля удалены');
    }

    await проверитьОбщийВидДоски(страница, '390 старт');
    проверить(красные.length === 0, '390 старт: консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));

    if (!fs.existsSync(ПАПКА_СНИМКОВ)) fs.mkdirSync(ПАПКА_СНИМКОВ, { recursive: true });
    const путьСнимка = path.join(ПАПКА_СНИМКОВ, 'шахматы-доска-из-набора-390-старт.png');
    await страница.screenshot({ path: путьСнимка });
    console.log('  снимок: ' + путьСнимка);

    await окно.close();
  }

  /* ----------------------------------------------------------------
     390×844 — ход e2–e4: подсветка последнего хода, поворот, буквы.
     Отдельная свежая страница: доска должна быть в начальной позиции,
     иначе e2–e4 может оказаться невозможным ходом.
     ---------------------------------------------------------------- */
  console.log('\n=== 390×844: ход e2–e4 — подсветка, поворот, aria-label ===');
  {
    const { окно, страница, красные } = await новая(браузер, 390, 844);
    await страница.click('#лобби-вдвоём');
    await спать(600);

    // Первый тап — только поднимает пешку, ход ещё не сделан: пешка
    // физически стоит на e2, и читалке экрана положено сказать именно
    // это (проверяем ДО второго тапа, иначе e2 уже станет пустой).
    await тапПоПолю(страница, 'e2');
    await спать(200);
    const меткаДоХода = await страница.evaluate(() => {
      const узел = document.querySelector('[data-поле="e2"]');
      return узел ? узел.getAttribute('aria-label') : null;
    });
    console.log('  aria-label поля e2 сразу после подъёма пешки: «' + меткаДоХода + '»');
    проверить(меткаДоХода === 'e2, белая пешка',
      'aria-label поднятой пешки на e2 — «e2, белая пешка», вышло «' + меткаДоХода + '»');

    await тапПоПолю(страница, 'e4');
    await спать(500);

    const послеХода = await страница.evaluate(() => {
      const e2 = document.querySelector('[data-поле="e2"]');
      const e4 = document.querySelector('[data-поле="e4"]');
      const буквы = [...document.querySelectorAll('.метка-буква')]
        .sort((а, б) => а.getBoundingClientRect().left - б.getBoundingClientRect().left)
        .map((у) => у.textContent.trim());
      return {
        e2Последний: !!(e2 && e2.classList.contains('поле--последний')),
        e4Последний: !!(e4 && e4.classList.contains('поле--последний')),
        доскаПеревёрнута: document.getElementById('доска').classList.contains('доска-шахмат--перевёрнута'),
        буквы: буквы
      };
    });
    console.log('  e2 «поле--последний»: ' + послеХода.e2Последний + ', e4: ' + послеХода.e4Последний +
      ', доска перевёрнута: ' + послеХода.доскаПеревёрнута + ', буквы снизу: ' + послеХода.буквы.join(''));
    проверить(послеХода.e2Последний, 'после e2–e4: клетка e2 несёт класс «поле--последний»');
    проверить(послеХода.e4Последний, 'после e2–e4: клетка e4 несёт класс «поле--последний»');
    проверить(послеХода.доскаПеревёрнута, 'после e2–e4 (играют вдвоём): доска повёрнута к чёрным');
    проверить(послеХода.буквы.join('') === 'hgfedcba',
      'после поворота буквы снизу идут h…a, вышло «' + послеХода.буквы.join('') + '»');
    проверить(красные.length === 0, 'ход e2–e4: консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));

    await окно.close();
  }

  /* ----------------------------------------------------------------
     390×844 — подъём коня b1: подсветка выбора и двух ходов.
     Тоже свежая страница: конь должен стоять на своём месте.
     ---------------------------------------------------------------- */
  console.log('\n=== 390×844: подъём коня b1 — выбор и куда можно ===');
  {
    const { окно, страница, красные } = await новая(браузер, 390, 844);
    await страница.click('#лобби-вдвоём');
    await спать(600);

    await тапПоПолю(страница, 'b1');
    await спать(300);

    const вид = await страница.evaluate(() => {
      const п = (имя) => document.querySelector('[data-поле="' + имя + '"]');
      const б1 = п('b1'); const a3 = п('a3'); const c3 = п('c3');
      return {
        b1Выбрано: !!(б1 && б1.classList.contains('поле--выбрано')),
        a3Можно: !!(a3 && a3.classList.contains('поле--можно')),
        c3Можно: !!(c3 && c3.classList.contains('поле--можно'))
      };
    });
    console.log('  b1 «поле--выбрано»: ' + вид.b1Выбрано + ', a3 «поле--можно»: ' + вид.a3Можно +
      ', c3 «поле--можно»: ' + вид.c3Можно);
    проверить(вид.b1Выбрано, 'после подъёма коня b1 — клетка b1 несёт «поле--выбрано»');
    проверить(вид.a3Можно, 'после подъёма коня b1 — клетка a3 несёт «поле--можно»');
    проверить(вид.c3Можно, 'после подъёма коня b1 — клетка c3 несёт «поле--можно»');
    проверить(красные.length === 0, 'конь b1: консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));

    await окно.close();
  }

  /* ----------------------------------------------------------------
     320×568 — узкий телефон: тот же вид доски и число — ширина клетки.
     ---------------------------------------------------------------- */
  console.log('\n=== 320×568: вид доски и ширина клетки ===');
  {
    const { окно, страница, красные } = await новая(браузер, 320, 568);
    await страница.click('#лобби-вдвоём');
    await спать(600);

    await проверитьОбщийВидДоски(страница, '320');

    const ширинаКлетки = await страница.evaluate(() =>
      Math.round(document.querySelector('.поле').getBoundingClientRect().width));
    console.log('  ширина клетки на 320: ' + ширинаКлетки + ' точек');
    проверить(ширинаКлетки >= 37 && ширинаКлетки <= 39,
      'ширина клетки на 320 — 37–39 точек, вышло ' + ширинаКлетки);
    проверить(красные.length === 0, '320: консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));

    await окно.close();
  }

  await браузер.close();
  console.log(СЛОМАТЬ ? '\n=== ИТОГ ЛОМАЮЩЕГО ЗАПУСКА ===' : '\n=== ИТОГ ОСНОВНЫХ ПРОВЕРОК ===');
  console.log('Итого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
})().catch((о) => { console.error('Стенд упал: ' + (о && о.stack || о)); process.exit(2); });
