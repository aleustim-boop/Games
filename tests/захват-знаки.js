'use strict';
// Проверка фраз «Захвата» (ТЗ, раздел 6) на node, без браузера.
// Запуск: node tests/захват-знаки.js            — настоящий файл + две порчи на копиях
//         node tests/захват-знаки.js --файл ПУТЬ — только указанная копия
const fs = require('fs');
const os = require('os');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const НАСТОЯЩИЙ = path.join(КОРЕНЬ, 'js', 'захват-знаки.js');
const ДЕБЕРЦ = path.join(КОРЕНЬ, 'js', 'деберц-знаки.js');
const КОМНАТА = path.join(КОРЕНЬ, 'server', 'комнаты.js');

// Фразы ТЗ, раздел 6, в порядке таблицы. Переписаны сюда руками: ТЗ — источник, тест — сторож.
const ФРАЗЫ_ТЗ = ['Мир?', 'Союз?', 'Согласен', 'Нет', 'Бьём лидера!', 'Предатель!', 'Помогите!', 'Хорошая игра'];

// Какие поля набора знаков читает комната: берём из кода самой функции послатьЗнакВнимания.
function полЯКомнаты() {
  const код = fs.readFileSync(КОМНАТА, 'utf8');
  const начало = код.indexOf('function послатьЗнакВнимания');
  const конец = код.indexOf('function записатьСобытие', начало);
  if (начало < 0 || конец < 0) return [];
  const кусок = код.slice(начало, конец);
  const поля = new Set();
  for (const m of кусок.matchAll(/(?<![\p{L}\d_.])знаки\.([\p{L}_]+)/gu)) поля.add(m[1]);
  // «знаки.push» — это время игрока, а не набор знаков: у игрока стоит «игрок.знаки», его
  // регулярка не берёт (перед точкой буква); всё же оставляем только то, что есть у деберца
  const деберц = require(ДЕБЕРЦ);
  return [...поля].filter(п => п in деберц);
}

function проверить(файл) {
  const строки = [];
  let всего = 0, провалов = 0;
  const да = (условие, что) => {
    всего++;
    if (!условие) { провалов++; строки.push('ПРОВАЛ: ' + что); }
  };
  let З;
  try { З = require(файл); } catch (e) { да(false, 'файл не загрузился: ' + e.message); return { всего, провалов, строки }; }
  const Д = require(ДЕБЕРЦ);

  // 1. Каждая фраза ТЗ на месте, по порядку, подряд
  да(Array.isArray(З.ФРАЗЫ), 'ФРАЗЫ — массив');
  const фразы = Array.isArray(З.ФРАЗЫ) ? З.ФРАЗЫ : [];
  да(фразы.length === ФРАЗЫ_ТЗ.length, 'число фраз ' + фразы.length + ', в ТЗ ' + ФРАЗЫ_ТЗ.length);
  ФРАЗЫ_ТЗ.forEach((ф, i) => {
    да(фразы[i] === ф, 'фраза №' + i + ' должна быть «' + ф + '», а там «' + фразы[i] + '»');
    const номер = Д.ЭМОЦИИ.length + i;
    да(З.текст(номер) === ф, 'текст(' + номер + ') должен быть «' + ф + '»');
    да(З.этоЗнак(номер) && !З.этоБросок(номер), 'номер ' + номер + ' — знак, но не бросок');
  });

  // 2. Номера стабильны: эмоции и броски те же, что у деберца, в тех же местах
  да(JSON.stringify(З.ЭМОЦИИ) === JSON.stringify(Д.ЭМОЦИИ), 'эмоции как у ДеберцЗнаки');
  да(JSON.stringify(З.БРОСКИ) === JSON.stringify(Д.БРОСКИ), 'броски как у ДеберцЗнаки');
  да(З.сколько() === З.ЭМОЦИИ.length + фразы.length + З.БРОСКИ.length, 'сколько() = эмоции + фразы + броски');
  const первыйБросок = З.ЭМОЦИИ.length + фразы.length;
  З.БРОСКИ.forEach((б, i) => {
    да(З.текст(первыйБросок + i) === б.имя, 'текст броска №' + i);
    да(З.предмет(первыйБросок + i) === б, 'предмет броска №' + i);
  });
  З.ЭМОЦИИ.forEach((э, i) => да(З.текст(i) === э, 'текст эмоции №' + i));

  // 3. Те же ответы по виду, что у ДеберцЗнаки, — по полям, которые читает комната
  const поля = полЯКомнаты();
  да(поля.length >= 3, 'из кода комнаты найдено полей набора: ' + поля.length + ' (нужно хотя бы 3: этоЗнак, этоБросок, сколько)');
  for (const п of поля) {
    да(typeof З[п] === typeof Д[п], 'поле «' + п + '» того же вида (' + typeof Д[п] + ')');
  }
  const пробы = [-1, 0, 1, 11, 12, 19, 20, 34, 35, 36, 1.5, NaN, Infinity, '3', '', null, undefined, {}, [], true];
  for (const п of ['этоЗнак', 'этоБросок']) {
    if (typeof З[п] !== 'function') { да(false, п + ' — функция'); continue; }
    for (const x of пробы) да(typeof З[п](x) === 'boolean', п + '(' + String(x) + ') отвечает да/нет');
  }
  да(typeof З.сколько() === 'number', 'сколько() — число');
  да(typeof З.текст(0) === 'string' && З.текст(9999) === '' && З.текст(-1) === '', 'текст: строка, а для чужого — пустая строка');
  да(З.предмет(0) === null && З.предмет(первыйБросок - 1) === null, 'предмет у эмоции и фразы — null');
  const п0 = З.предмет(первыйБросок);
  да(п0 && ['ключ', 'имя', 'винительный', 'злой'].every(к => к in п0), 'у предмета есть ключ, имя, винительный, злой');

  // 4. Границы: чужой номер не знак
  const n = З.сколько();
  да(З.этоЗнак(0) && З.этоЗнак(n - 1), 'первый и последний номера — знаки');
  да(!З.этоЗнак(n), 'этоЗнак(' + n + ') — «нет» (чужой номер)');
  да(!З.этоЗнак(-1) && !З.этоЗнак(1.5) && !З.этоЗнак('3') && !З.этоЗнак(null), 'этоЗнак отвечает «нет» на мусор');
  да(!З.этоБросок(первыйБросок - 1) && З.этоБросок(первыйБросок) && З.этоБросок(n - 1) && !З.этоБросок(n), 'граница бросков');

  // 5. Файл без document, Date, Math.random
  const текстФайла = fs.readFileSync(файл, 'utf8');
  да(!/\bdocument\b|\bDate\b|Math\.random/.test(текстФайла), 'в файле нет document, Date, Math.random');
  да(/window\.ЗахватЗнаки\s*=/.test(текстФайла) && /module\.exports\s*=/.test(текстФайла), 'есть и window.ЗахватЗнаки, и module.exports');
  return { всего, провалов, строки };
}

function сделатьПорчу(имя, заменить, на) {
  const текст = fs.readFileSync(НАСТОЯЩИЙ, 'utf8');
  if (!текст.includes(заменить)) throw new Error('порча «' + имя + '»: не нашла, что портить');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-знаки-'));
  const копия = path.join(папка, 'захват-знаки.js');
  fs.writeFileSync(копия, текст.replace(заменить, на));
  return копия;
}

function вывести(р) { р.строки.forEach(с => console.log('  ' + с)); }

const аргументы = process.argv.slice(2);
const номерДовода = аргументы.indexOf('--файл');
if (номерДовода >= 0) {
  const файл = аргументы[номерДовода + 1];
  if (!файл) { console.log('после --файл нужен путь'); process.exit(2); }
  const р = проверить(path.resolve(файл));
  вывести(р);
  console.log('проверок: ' + р.всего + ', провалов: ' + р.провалов);
  process.exit(р.провалов ? 1 : 0);
}

let итогПровалов = 0;
const основной = проверить(НАСТОЯЩИЙ);
вывести(основной);
console.log('настоящий файл: проверок ' + основной.всего + ', провалов ' + основной.провалов);
итогПровалов += основной.провалов;

const порчи = [
  ['пропала фраза «Мир?»', "  'Мир?',               // предложить не бить друг друга\n", ''],
  ['этоЗнак пропускает чужой номер', 'n < список.length;', 'n < список.length + 1;']
];
for (const [имя, что, на] of порчи) {
  const р = проверить(сделатьПорчу(имя, что, на));
  console.log('порча «' + имя + '»: проверок ' + р.всего + ', провалов ' + р.провалов);
  if (р.провалов === 0) { console.log('  ПРОВАЛ: порча не покраснела — проверка бессильна'); итогПровалов++; }
}
console.log(итогПровалов ? 'ИТОГ: ПРОВАЛ' : 'ИТОГ: зелено');
process.exit(итогПровалов ? 1 : 0);
