function телоОпросаИзСети(текст) {
  const вызов = текст.match(/запросОтМеня\('\/что-нового',\s*([^\s,()]+)\s*,/);
  if (!вызов) return { ошибка: 'вызов запросОтМеня(\'/что-нового\', …) не найден' };
  const присвоение = текст.match(new RegExp('const ' + вызов[1] + ' = ([^\\s(),=;]+)\\(\\);'));
  if (!присвоение) return { ошибка: 'не найдено, откуда берётся «' + вызов[1] + '»' };
  const сборщик = текст.match(new RegExp('function ' + присвоение[1] + '\\(\\) \\{\\s*return \\{([^}]*)\\};'));
  if (!сборщик) return { ошибка: 'не найден сборщик «' + присвоение[1] + '»' };
  const поля = {};
  const поле = /([^\s:,{}]+):\s*([^\n]+?),?\s*$/gm;
  let найдено;
  while ((найдено = поле.exec(сборщик[1])) !== null) поля[найдено[1]] = найдено[2].trim();
  return { поля: поля };
}
