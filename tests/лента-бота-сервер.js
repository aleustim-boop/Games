/**
 * Внешние адреса этой машины (IPv4 не внутренние). По ним сосед по сети
 * стучался бы к серверу, слушай тот все входы.
 */
function внешниеАдреса() {
  const итог = [];
  const сети = os.networkInterfaces();
  for (const имя of Object.keys(сети)) {
    for (const а of сети[имя] || []) {
      if (а.family === 'IPv4' && !а.internal) итог.push(а.address);
    }
  }
  return итог;
}

function постучаться(хост, порт) {
  return new Promise(function (готово) {
    const гнездо = require('net').connect({ host: хост, port: порт });
    const сторож = setTimeout(function () { гнездо.destroy(); готово(false); }, 1500);
    гнездо.once('connect', function () { clearTimeout(сторож); гнездо.destroy(); готово(true); });
    гнездо.once('error', function () { clearTimeout(сторож); готово(false); });
  });
}

/**
 * Свободен ли порт прямо сейчас. сервера.запустить при занятом порту сам
 * завершает процесс (process.exit) — если звать её не проверив заранее,
 * проверка обрывается молча, без итоговой строки. Пробуем открыть порт
 * сами: получилось — закрываем и отдаём его настоящему вызову; не вышло —
 * сообщаем понятную причину и не подставляемся под чужой process.exit.
 */
function портСвободен(порт) {
  return new Promise(function (готово) {
    const проба = require('net').createServer();
    проба.once('error', function () { готово(false); });
    проба.once('listening', function () { проба.close(function () { готово(true); }); });
    проба.listen(порт, ХОСТ);
  });
}

/* --- 9. Настоящий запуск слушает только свой компьютер --- */
async function проверитьПрослушку() {
  console.log('9. сервера.запустить слушает только 127.0.0.1');
  const порт = ПОРТ + 2;
  if (!(await портСвободен(порт))) {
    проверить(false, '9: порт ' + порт + ' занят другим процессом — сервера.запустить не проверен ' +
      '(освободите порт или передайте другой ПОРТ первым доводом)');
    return;
  }
  const живой = сервера.запустить(порт);
  await new Promise(function (готово) {
    if (живой.listening) готово(); else живой.once('listening', готово);
  });
  const адрес = живой.address();
  проверить(адрес && адрес.address === '127.0.0.1',
    '9: адрес прослушки 127.0.0.1 (вышло: ' + (адрес && адрес.address) + ')');
  проверить(await постучаться('127.0.0.1', порт), '9: по 127.0.0.1 сервер отвечает');
  const внешние = внешниеАдреса();
  if (внешние.length === 0) {
    console.log('  (внешних адресов у машины нет — стук снаружи не проверить, сверка адреса выше остаётся)');
  }
  for (const внешний of внешние) {
    проверить(!(await постучаться(внешний, порт)), '9: по внешнему адресу ' + внешний + ' не достучаться');
  }
  await new Promise(function (готово) { живой.close(готово); });
  комнаты.остановитьУборку();
}

