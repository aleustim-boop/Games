function подписать(поля, токен) {
  const строки = Object.keys(поля).filter(function (к) { return к !== 'hash'; })
    .map(function (к) { return к + '=' + поля[к]; }).sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(токен).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}

function подписьИгрока(номер, имя) {
  const поля = {
    query_id: 'AAF' + номер,
    user: JSON.stringify({ id: номер, first_name: имя, username: 'igrok' + номер }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  const сподписью = Object.assign({}, поля, { hash: подписать(поля, ТОКЕН_ДЛЯ_ПРОБЫ) });
  return Object.keys(сподписью)
    .map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(сподписью[к]); })
    .join('&');
}

/**
 * Ссылка за стол, как её собирает js/сеть.js (ссылкаНаМиниПриложение).
 * что: { бот, метка, адрес } — адрес null значит «без хвоста».
 */
function ссылкаЗаСтол(код, что) {
  const н = что || {};
  const адрес = н.адрес === undefined ? СВОЙ_АДРЕС : н.адрес;
  return 'https://t.me/' + (н.бот || ИМЯ_БОТА) + '/BoardGames?startapp=' +
    (н.метка ? н.метка + '_' : '') + код + (адрес ? '-' + адресБуквами(адрес) : '');
}

/** Обычный запрос: ждём ответ целиком. */
function спросить(путь, тело) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОСТ, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (сбой) { разобрано = null; }
        готово({ код: ответ.statusCode, тело: разобрано || {}, текст: текст });
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

/** Длинный опрос, который держим открытым. Возвращает функцию «бросить». */
function открытьОпрос(тело) {
  const данные = Buffer.from(JSON.stringify(тело), 'utf8');
  const запрос = http.request({
    host: ХОСТ, port: ПОРТ, path: encodeURI('/что-нового'), method: 'POST',
    headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
  }, function (ответ) { ответ.resume(); });
  запрос.on('error', function () { /* бросили сами — это нормально */ });
  запрос.write(данные);
  запрос.end();
  return function () { запрос.destroy(); };
}

/**
 * Прислать ссылку в /что-нового, как будет слать страница. Версия -1 —
 * ответ приходит сразу, поэтому время ответа меряет только работу сервера.
 */
async function прислатьСсылку(место, ссылка) {
  const начало = performance.now();
  const ответ = await спросить('/что-нового', { код: место.код, пропуск: место.пропуск, версия: -1, ссылка: ссылка });
  return { ответ: ответ, мс: Math.round(performance.now() - начало) };
}

async function создатьСтол(номер, имя, ещё) {
  const ответ = await спросить('/создать', Object.assign({
    initData: подписьИгрока(номер, имя), имя: 'Игра' + имя
  }, ещё || {}));
  return { код: ответ.тело.код || '', пропуск: ответ.тело.пропуск || '', ответ: ответ };
}

async function войтиЗаСтол(код, номер, имя, ещё) {
  const тело = Object.assign({ код: код, имя: 'Игра' + имя }, ещё || {});
  if (номер) тело.initData = подписьИгрока(номер, имя);
  const ответ = await спросить('/войти', тело);
  return { код: ответ.тело.код || '', пропуск: ответ.тело.пропуск || '', ответ: ответ };
}

/** Игрок «отошёл»: молчит дольше, чем считается «у экрана». */
function замолчать(место) {
  const н = комнаты.найтиИгрока(место.код, место.пропуск);
  if (н) н.комната.игроки[н.ктоЯ].последнийЗапрос = Date.now() - ДАЛЁКОЕ_МОЛЧАНИЕ;
}

/**
 * Какую ссылку запомнил стол. Смотрим прямо в комнату; найтиИгрока отмечает
 * «жив», поэтому время последнего запроса возвращаем как было.
 */
function ссылкаСтолаМолча(место) {
  const н = комнаты.найтиИгрока(место.код, место.пропуск);
  if (!н) return undefined;
  const игрок = н.комната.игроки[н.ктоЯ];
  const было = игрок.последнийЗапрос;
  const ссылка = н.комната.ссылкаЗаСтол;
  игрок.последнийЗапрос = было;
  return ссылка;
}

/** Партию считаем доигранной, не играя её: «ещё» ждёт только этап «конец». */
function доиграть(место) {
  const н = комнаты.найтиИгрока(место.код, место.пропуск);
  if (н) н.комната.этап = 'конец';
}

async function версияСтола(место) {
  const ответ = await спросить('/состояние', { код: место.код, пропуск: место.пропуск });
  return ответ.тело.состояние ? ответ.тело.состояние.версия : 0;
}

/** Кнопки письма: [«текст кнопки», url | callback]. */
function кнопкиПисьма(запись) {
  const ряды = (запись.тело.reply_markup && запись.тело.reply_markup.inline_keyboard) || [];
  return ряды.map(function (ряд) { return ряд[0]; });
}

/** Сверить одно письмо с тем, что собирает сама лента из тех же данных. */
function сверитьПисьмо(запись, данные, что) {
  const ждём = лента.собратьПисьмо(данные);
  проверить(Boolean(запись) && запись.тело.text === ждём.текст,
    что + ': текст письма как у ленты («' + ждём.текст + '»)' +
    (запись ? '' : ' — письма нет'));
  проверить(Boolean(запись) &&
    JSON.stringify(запись.тело.reply_markup) === JSON.stringify(ждём.кнопки),
    что + ': кнопки письма как у ленты');
  const кнопки = запись ? кнопкиПисьма(запись) : [];
  проверить(кнопки.some(function (к) { return к.callback_data === лента.ОТКАЗ_ОТ_ЗОВОВ; }),
    что + ': в письме есть «Не звать меня»');
  const открыть = кнопки.find(function (к) { return к.text === 'Открыть стол'; });
  if (данные.ссылка) {
    проверить(Boolean(открыть) && открыть.url === данные.ссылка,
      что + ': «Открыть стол» ведёт на проверенную ссылку');
  } else {
    проверить(Boolean(запись) && !открыть, что + ': кнопки «Открыть стол» нет');
  }
}

