function поддельныйTelegram(метод, тело) {
  if (метод === 'getMe') {
    журнал.push({ метод: метод, тело: тело });
    if (getMeНедоступен) {
      return new Promise(function (готово) {
        setTimeout(function () { готово(null); }, GETME_ВИСИТ);
      });
    }
    return { ok: true, result: { id: 777, is_bot: true, username: ИМЯ_БОТА } };
  }
  if (метод === 'sendMessage') {
    const запись = Object.assign({}, тело);
    if (ЛОМАТЬ) запись.chat_id = ЧУЖОЙ_НОМЕР;
    журнал.push({ метод: метод, тело: запись });
    if (комуНеПишем.has(Number(тело && тело.chat_id))) {
      return { ok: false, error_code: 403, description: 'Forbidden: bot was blocked by the user' };
    }
    return { ok: true, result: { message_id: журнал.length } };
  }
  return { ok: false, error_code: 400, description: 'Bad Request' };
}

