/** Обычный запрос: ждём ответ целиком. хост — подменить заголовок Host (как туннель). */
function спросить(путь, тело, хост) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const заголовки = { 'Content-Type': 'application/json', 'Content-Length': данные.length };
    if (хост) заголовки.Host = хост;
    const запрос = http.request({
      host: ХОСТ, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: заголовки
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (сбой) { разобрано = null; }
        готово({ код: ответ.statusCode, тело: разобрано || {}, текст: текст });
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

/** Длинный опрос, который держим открытым. Возвращает функцию «бросить». */
function открытьОпрос(тело) {
  const данные = Buffer.from(JSON.stringify(тело), 'utf8');
  const запрос = http.request({
    host: ХОСТ, port: ПОРТ, path: encodeURI('/что-нового'), method: 'POST',
    headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
  }, function (ответ) { ответ.resume(); });
  запрос.on('error', function () { /* бросили сами — это нормально */ });
  запрос.write(данные);
  запрос.end();
  return function () { запрос.destroy(); };
}

/**
 * Длинный опрос, за ответом которого можно проследить (в отличие от
 * открытьОпрос выше — та только резюмирует и ответ никак не разбирает).
 * Нужен для проверки отсрочки перед «пропал»: важно поймать МОМЕНТ,
 * когда сервер разбудил ожидание, а не просто повисеть и оборвать.
 * Возвращает { исход, бросить } — исход разрешается телом ответа.
 */
function держатьОпрос(тело) {
  const начало = performance.now();
  let завершить;
  const исход = new Promise(function (готово) { завершить = готово; });
  const данные = Buffer.from(JSON.stringify(тело), 'utf8');
  const запрос = http.request({
    host: ХОСТ, port: ПОРТ, path: encodeURI('/что-нового'), method: 'POST',
    headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
  }, function (ответ) {
    let текст = '';
    ответ.on('data', function (кусок) { текст += кусок; });
    ответ.on('end', function () {
      let разобрано = null;
      try { разобрано = JSON.parse(текст || '{}'); } catch (сбой) { разобрано = null; }
      завершить({ тело: разобрано || {}, мс: Math.round(performance.now() - начало) });
    });
  });
  запрос.on('error', function () { /* оборвали сами — это нормально, исход просто не наступит */ });
  запрос.write(данные);
  запрос.end();
  return { исход: исход, бросить: function () { запрос.destroy(); } };
}

/**
 * Прислать ссылку в /что-нового, как будет слать страница. Версия -1 —
 * ответ приходит сразу, поэтому время ответа меряет только работу сервера.
 */
async function прислатьСсылку(место, ссылка) {
  const начало = performance.now();
  const ответ = await спросить('/что-нового', { код: место.код, пропуск: место.пропуск, версия: -1, ссылка: ссылка });
  return { ответ: ответ, мс: Math.round(performance.now() - начало) };
}

/**
 * Тело /что-нового ровно с теми полями, что собирает js/сеть.js (ТЕЛО_ОПРОСА).
 * Значение каждому полю — то, что страница положила бы за этим столом:
 * ссылка — как у ссылкаНаМиниПриложение (ссылкаЗаСтол выше), скрыта — как велено.
 * Поле, которого проверка не знает, остаётся пустым и отмечается провалом.
 */
function телоКакУСети(место, версия, скрыта) {
  const тело = { код: место.код, пропуск: место.пропуск };
  const поля = ТЕЛО_ОПРОСА.поля || {};
  for (const имя of Object.keys(поля)) {
    if (имя === 'версия') тело.версия = версия;
    else if (имя === 'ссылка') тело.ссылка = ссылкаЗаСтол(место.код);
    else if (имя === 'скрыта') тело.скрыта = скрыта;
    else проверить(false, 'поле «' + имя + '» из тела опроса js/сеть.js проверке незнакомо');
  }
  return тело;
}

