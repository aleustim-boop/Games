/* ---------- Ломающий прогон ---------- */

function сделатьКопиюПроекта(папка) {
  for (const часть of ['server', 'js', 'img', 'шрифты']) {
    const откуда = path.join(ПРОЕКТ, часть);
    if (!fs.existsSync(откуда)) continue;
    fs.cpSync(откуда, path.join(папка, часть), {
      recursive: true,
      filter: function (ф) { const имя = path.basename(ф); return имя !== 'данные' && имя !== 'node_modules'; }
    });
  }
  for (const файл of fs.readdirSync(ПРОЕКТ)) {
    if (файл.endsWith('.html') || файл.endsWith('.css')) fs.copyFileSync(path.join(ПРОЕКТ, файл), path.join(папка, файл));
  }
}

function ломать() {
  console.log('=== Ломающий прогон: шашки.html без js/дурак-комната.js — обязан покраснеть ===');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'шашки-как-дурак-лом-'));
  сделатьКопиюПроекта(папка);
  const файл = path.join(папка, 'шашки.html');
  const текст = fs.readFileSync(файл, 'utf8');
  if (!СТРОКА_КОМНАТЫ.test(текст)) {
    console.log('ПРОВАЛ: в копии шашки.html нет подключения js/дурак-комната.js — портить нечего');
    process.exit(1);
  }
  fs.writeFileSync(файл, текст.replace(СТРОКА_КОМНАТЫ, ''), 'utf8');
  console.log('Порченая копия: ' + папка);
  const прогон = spawnSync(process.execPath, [__filename, '--корень', папка], { encoding: 'utf8', timeout: 180000 });
  console.log('\n----- вывод ломающего прогона -----\n' + (прогон.stdout || '') + (прогон.stderr ? 'stderr: ' + прогон.stderr : ''));
  console.log('------------------------------------');
  const покраснел = прогон.status === 1;
  console.log(покраснел
    ? 'ЛОМАЮЩИЙ ПРОГОН ПОКРАСНЕЛ, КАК И ДОЛЖЕН (код выхода 1).'
    : 'ПРОВАЛ: ломающий прогон не покраснел (код выхода ' + прогон.status + ') — проверка не ловит поломку!');
  process.exit(покраснел ? 0 : 1);
}

/* ---------- Обычный прогон ---------- */

async function прогнать(корень) {
  // Снимки настоящего прогона — в tests/снимки/; ломающий пишет внутрь своей копии.
  const настоящий = path.resolve(корень).toLowerCase() === path.resolve(ПРОЕКТ).toLowerCase();
  const папкаСнимков = настоящий ? path.join(ПАПКА_ПРОВЕРОК, 'снимки') : path.join(корень, '_снимки-ломающего-прогона');
  fs.mkdirSync(папкаСнимков, { recursive: true });
  console.log('=== Шашки онлайн как дурак — проверка в браузере ===');
  console.log('корень: ' + корень + '\nфайлы: ' + АДРЕС_ФАЙЛОВ + ', комнаты: ' + АДРЕС_КОМНАТ + ' (не боевой 8790)');

  const файловый = await поднятьФайловыйСервер(корень);
  let серверКомнат = null;
  let браузер = null;
  try {
    серверКомнат = await поднятьСерверКомнат(корень);
    браузер = await chromium.launch();
    await сценарий(браузер, папкаСнимков);
  } finally {
    if (браузер) await браузер.close();
    файловый.kill();
    if (серверКомнат) {
      серверКомнат.closeAllConnections();
      серверКомнат.close();
    }
    console.log('\nФайловый сервер погашен по PID ' + файловый.pid + ', сервер комнат ' + ПОРТ_КОМНАТ + ' закрыт.');
  }
  console.log('\nИтого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
  process.exit(провалов > 0 ? 1 : 0);
}

function доводПосле(имя) {
  const где = process.argv.indexOf(имя);
  return где !== -1 ? process.argv[где + 1] : null;
}

