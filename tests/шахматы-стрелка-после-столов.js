const path = require('path');
const fs = require('fs');
const { spawn } = require('child_process');
const { chromium, подготовитьПодделку, перехватить } = require('./браузер-робот.js');

const КОРЕНЬ = path.join(__dirname, '..');
const СЛОМАТЬ = process.argv.includes('--сломать');
const числовойДовод = process.argv.slice(2).find(function (а) { return /^\d+$/.test(а); });
const ПОРТ = Number(числовойДовод) || 8834;
const ОСНОВА = 'http://127.0.0.1:' + ПОРТ + '/';
const МИН_ПРОВЕРОК = 60;   // нижний порог: меньше — значит сценарии молча не дошли

let проверок = 0;
let провалов = 0;
const красныеПункты = [];

function проверить(условие, слова) {
  проверок++;
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) { провалов++; красныеПункты.push(слова); }
}
const спать = function (мс) { return new Promise(function (г) { setTimeout(г, мс); }); };

/* ---------------------------------------------------------------------
   Ломающий запуск: копия js/шахматы-экран.js без вызова
   освежитьСтрелкуНазад() в показатьПоИмени.
   --------------------------------------------------------------------- */
const СТРОКА_ВЫЗОВА = /^[ \t]*if \(стрелкуУнёсЧужойЭкран\) освежитьСтрелкуНазад\(\);[ \t]*$/m;
let сломаннаяКопия = null;
let сколькоРазПодменено = 0;

function собратьСломаннуюКопию() {
  const исходный = fs.readFileSync(path.join(КОРЕНЬ, 'js', 'шахматы-экран.js'), 'utf8');
  const порча = исходный.replace(СТРОКА_ВЫЗОВА, '    /* ломающий запуск: вызов освежитьСтрелкуНазад убран */');
  if (порча === исходный) return null;   // места правки нет — вызывающий обязан покраснеть
  return порча;
}

