function поднятьСервер() {
  return new Promise(function (готово, беда) {
    const дитя = spawn('node', [path.join(КОРЕНЬ, 'tests', 'локальный-сервер.js'), String(ПОРТ)]);
    let вывод = '';
    const срок = setTimeout(function () {
      дитя.kill();
      беда(new Error('локальный сервер не поднялся за 8 секунд'));
    }, 8000);
    дитя.stdout.on('data', function (кусок) {
      вывод += кусок;
      if (/сервер запущен/.test(вывод)) { clearTimeout(срок); готово(дитя); }
    });
    дитя.on('error', беда);
  });
}

async function новаяСтраница(браузер) {
  const контекст = await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
  const страница = await контекст.newPage();
  const красные = [];
  страница.on('pageerror', function (о) { красные.push('падение: ' + о.message); });
  страница.on('console', function (м) {
    if (м.type() !== 'error') return;
    const текст = м.text();
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js/.test(текст + ' ' + откуда)) return;
    // Сервера комнат в этой проверке нет — красная строка браузера про
    // неудавшийся запрос к нему (сеть, не наш код) не в счёт.
    if (/Failed to load resource|net::ERR|ERR_CONNECTION|ERR_ABORTED/.test(текст)) return;
    красные.push('консоль: ' + текст);
  });
  await подготовитьПодделку(страница, { версия: '8.0' });
  if (СЛОМАТЬ) {
    if (сломаннаяКопия !== null) {
      await перехватить(страница, /\/js\/шахматы-экран\.js(?:\?|$)/, function (путь) {
        сколькоРазПодменено++;
        путь.fulfill({ status: 200, contentType: 'application/javascript; charset=utf-8', body: сломаннаяКопия });
      });
    }
  }
  return { контекст: контекст, страница: страница, красные: красные };
}

async function дождатьсяЭкрана(страница, id, мс) {
  try {
    await страница.waitForFunction(function (и) {
      const э = document.getElementById(и);
      return Boolean(э && э.classList.contains('экран--виден'));
    }, id, { timeout: мс || 5000 });
    return true;
  } catch (сбой) {
    return false;
  }
}

/** Нажать стрелку Telegram — тем же приёмом, что настоящее нажатие. */
async function нажатьСтрелку(страница) {
  return страница.evaluate(function () {
    if (!window.ПоддельныйТелеграм) return false;
    window.ПоддельныйТелеграм.нажатьНазад();
    return true;
  });
}

async function путь(страница) {
  try { return await страница.evaluate(function () { return location.pathname; }); }
  catch (сбой) { return null; }   // страница уже уходит — контекст мог умереть
}

/** Нажать кнопку по id: не нашлась — провал (ноль найденного). */
async function нажатьУзел(страница, селектор, слова, программно) {
  const сколько = await страница.locator(селектор).count();
  проверить(сколько > 0, 'нашёлся узел «' + слова + '» (' + селектор + '), не ноль: ' + сколько);
  if (сколько === 0) return false;
  try {
    // Кнопки «Назад»/«Отменить» экранов столов и подбора в Telegram (а у нас
    // поддельный Telegram ставит тот же класс) спрятаны стилем: там их заменяет
    // системная стрелка, а «Отменить» на подборе без сервера гаснет за доли
    // секунды. Палец до них не дотянется, поэтому нажимаем программно —
    // тем же обработчиком, что и палец. Остальные узлы жмём настоящим кликом.
    if (программно) await страница.locator(селектор).first().evaluate(function (э) { э.click(); });
    else await страница.locator(селектор).first().click({ timeout: 4000 });
  } catch (сбой) {
    проверить(false, 'узел «' + слова + '» нажимается пальцем (' + (сбой.message || '').split('\n')[0] + ')');
    return false;
  }
  return true;
}

/** Стрелка на лобби уводит на витрину? Одно нажатие, ждём смену адреса. */
async function стрелкаУводитНаВитрину(страница, метка) {
  const до = await путь(страница);
  проверить(до !== null && /шахматы\.html/.test(decodeURIComponent(до)),
    метка + ': перед нажатием мы на шахматы.html (' + до + ')');
  await нажатьСтрелку(страница);
  const край = Date.now() + 3500;
  let после = до;
  while (Date.now() < край) {
    после = await путь(страница);
    if (после === null || после !== до) break;
    await спать(120);
  }
  await спать(150);
  const итог = (await путь(страница)) || '';
  проверить(/index\.html|^\/$/.test(итог),
    метка + ': нажатие стрелки на лобби увело на витрину (было ' + до + ', стало ' + (итог || 'страница уходит') + ')');
}

async function открытьЛобби(браузер, имя) {
  console.log('\n=== ' + имя + ' ===');
  const набор = await новаяСтраница(браузер);
  await набор.страница.goto(ОСНОВА + 'шахматы.html');
  const лобби = await дождатьсяЭкрана(набор.страница, 'экран-лобби', 6000);
  проверить(лобби, имя + ': лобби шахмат показалось после загрузки');
  набор.лобби = лобби;
  return набор;
}

async function войтиВСтолы(страница, метка) {
  const нажато = await нажатьУзел(страница, '#лобби-найти-игру', 'Найти игру в лобби');
  const открыты = нажато && await дождатьсяЭкрана(страница, 'экран-открытые-столы', 5000);
  проверить(Boolean(открыты), метка + ': «Найти игру» открыла список открытых столов');
  return Boolean(открыты);
}

async function вернулисьВЛобби(страница, метка) {
  const ок = await дождатьсяЭкрана(страница, 'экран-лобби', 4000);
  проверить(ок, метка);
  return ок;
}

