/** Сервер комнат — модулем в этом же процессе (как tests/шахматы-как-дурак-браузер.js). Данные — в свою временную папку. */
function поднятьСерверКомнат() {
  папкаДанных = path.join(os.tmpdir(), 'шахматы-стрелка-столов-' + process.pid);
  process.env.ДАННЫЕ_ИГРЫ = папкаДанных;   // до require: боевых данных не касаемся
  const модуль = require(path.join(КОРЕНЬ, 'server', 'сервер.js'));
  модульКомнат = require(path.join(КОРЕНЬ, 'server', 'комнаты.js'));
  модуль.оснасткаДляПроверки(ТОКЕН_ДЛЯ_ПРОБЫ, function () { return { ok: true }; });
  const сервер = модуль.создатьСервер();
  return new Promise(function (готово, беда) {
    сервер.once('error', беда);
    сервер.listen(ПОРТ_КОМНАТ, '127.0.0.1', function () { серверКомнат = сервер; готово(сервер); });
  });
}

async function погаситьСерверКомнат() {
  if (серверКомнат) {
    try { серверКомнат.closeAllConnections(); } catch (сбой) { /* старый Node — не страшно */ }
    await new Promise(function (г) { серверКомнат.close(function () { г(); }); setTimeout(г, 1500); });
  }
  if (папкаДанных) { try { fs.rmSync(папкаДанных, { recursive: true, force: true }); } catch (сбой) { /* нет папки — нечего убирать */ } }
}

/** Спросить сервер: жива ли комната с таким кодом (GET /стол). null — сервер не ответил. */
function спроситьСтол(код) {
  return new Promise(function (готово) {
    const адрес = new URL(АДРЕС_КОМНАТ + '/стол?код=' + encodeURIComponent(код));
    http.get(адрес, function (ответ) {
      let текст = '';
      ответ.on('data', function (д) { текст += д; });
      ответ.on('end', function () { try { готово(JSON.parse(текст)); } catch (сбой) { готово(null); } });
    }).on('error', function () { готово(null); });
  });
}

/** Ждать, пока ответ сервера про стол не станет «как надо». Возвращает { ок, стол } — последний ответ. */
async function ждатьСтол(код, годится, мс) {
  const край = Date.now() + (мс || 5000);
  let стол = null;
  while (true) {
    стол = await спроситьСтол(код);
    if (стол && годится(стол)) return { ок: true, стол: стол };
    if (Date.now() > край) return { ок: false, стол: стол };
    await спать(150);
  }
}

