(async () => {
  console.log('=== Проверка: шахматы, стрелка «назад» после «Найти игру» и подбора ===');
  console.log(СЛОМАТЬ ? '(ЛОМАЮЩИЙ ЗАПУСК --сломать: браузеру отдаётся копия js/шахматы-экран.js без освежитьСтрелкуНазад() в показатьПоИмени)'
    : '(обычный запуск)');

  if (СЛОМАТЬ) {
    сломаннаяКопия = собратьСломаннуюКопию();
    проверить(сломаннаяКопия !== null,
      'ломающий запуск: в js/шахматы-экран.js нашлась строка «if (стрелкуУнёсЧужойЭкран) освежитьСтрелкуНазад();» — есть что убирать');
  }

  const сервер = await поднятьСервер();
  const браузер = await chromium.launch();
  try {
    await сценарийА(браузер);
    await сценарийБ(браузер);
    await сценарийВ(браузер, 'кнопка');
    await сценарийВ(браузер, 'стрелка');
    await сценарийГ(браузер, 'стрелка', 'кнопка');
    await сценарийГ(браузер, 'отменить', 'стрелка');
    await сценарийГ(браузер, 'назад', 'стрелка');
    await сценарийД(браузер);
  } finally {
    await браузер.close();
    сервер.kill();
  }

  if (СЛОМАТЬ) {
    проверить(сколькоРазПодменено > 0,
      'ломающий запуск: перехват сработал — браузер получил сломанную копию файла ' + сколькоРазПодменено + ' раз(а), не ноль');
  }

  console.log('\n----------------------------------------');
  if (!СЛОМАТЬ) {
    // Нижний порог: слишком мало проверок = сценарии молча не дошли.
    проверить(проверок + 1 >= МИН_ПРОВЕРОК,
      'число проверок не ниже порога ' + МИН_ПРОВЕРОК + ' (сейчас ' + (проверок + 1) + ')');
  }
  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
  if (СЛОМАТЬ) {
    // Ломающий запуск обязан покраснеть именно на сути (стрелка не увела на витрину),
    // а не только на служебных проверках.
    const покраснелоПоСути = красныеПункты.some(function (п) { return /увело на витрину/.test(п); });
    console.log(покраснелоПоСути
      ? 'ИТОГ ЛОМАЮЩЕГО ЗАПУСКА: покраснело по существу — стрелка не увела на витрину.'
      : 'ИТОГ ЛОМАЮЩЕГО ЗАПУСКА: ПРОВЕРКА СЛЕПАЯ — «стрелка увела на витрину» не покраснела.');
    process.exit(провалов && покраснелоПоСути ? 1 : 3);
  }
  process.exit(провалов ? 1 : 0);
})().catch(function (о) {
  console.error('Стенд упал: ' + (о && о.stack || о));
  process.exit(2);
});
