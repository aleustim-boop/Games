/** Общий путь В: со столов выходим по-разному, потом «Рейтинг» и обратно. */
async function сценарийВ(браузер, какВыйти) {
  const имя = 'В (' + какВыйти + '). столы → выход → «Рейтинг» → стрелка → лобби → стрелка';
  const н = await открытьЛобби(браузер, имя);
  try {
    if (!н.лобби) return;
    const п = н.страница;
    if (!await войтиВСтолы(п, 'В/' + какВыйти)) return;
    if (какВыйти === 'кнопка') await нажатьУзел(п, '#открытые-столы-назад', 'Назад на списке столов', true);
    else await нажатьСтрелку(п);
    if (!await вернулисьВЛобби(п, 'В/' + какВыйти + ': со столов вернулись в лобби')) return;

    const вкладка = await нажатьУзел(п, '[data-нижняя-вкладка-действие="рейтинг-шахматы"]', 'вкладка «Рейтинг» на нижней полосе');
    if (!вкладка) return;
    const рейтинг = await дождатьсяЭкрана(п, 'экран-рейтинга-игроков', 5000);
    проверить(рейтинг, 'В/' + какВыйти + ': «Рейтинг» после столов открылся');
    if (!рейтинг) return;

    await нажатьСтрелку(п);
    if (!await вернулисьВЛобби(п, 'В/' + какВыйти + ': стрелка из рейтинга (после столов) вернула в лобби')) return;
    await стрелкаУводитНаВитрину(п, 'В/' + какВыйти);
    проверить(н.красные.length === 0, 'В/' + какВыйти + ': консоль чистая' + (н.красные.length ? ': ' + н.красные.join(' | ') : ''));
  } finally { await н.контекст.close(); }
}

/** Г: экран подбора соперника (сервера комнат нет — проверяем только выходы). */
async function сценарийГ(браузер, какВыйтиСПодбора, какВыйтиСоСтолов) {
  const имя = 'Г (подбор: ' + какВыйтиСПодбора + ', столы: ' + какВыйтиСоСтолов + '). лобби → столы → подбор → назад → лобби → стрелка';
  const н = await открытьЛобби(браузер, имя);
  const метка = 'Г/' + какВыйтиСПодбора + '+' + какВыйтиСоСтолов;
  try {
    if (!н.лобби) return;
    const п = н.страница;
    if (!await войтиВСтолы(п, метка)) return;
    const нажатоПодбор = await нажатьУзел(п, '#открытые-столы-подбор', 'кнопка подбора соперника на списке столов');
    if (!нажатоПодбор) return;
    const подбор = await дождатьсяЭкрана(п, 'экран-подбор-соперника', 5000);
    проверить(подбор, метка + ': открылся экран подбора соперника');
    if (!подбор) return;

    if (какВыйтиСПодбора === 'стрелка') {
      await нажатьСтрелку(п);
    } else if (какВыйтиСПодбора === 'отменить') {
      await нажатьУзел(п, '#подбор-отмена', 'кнопка «Отменить» на подборе', true);
    } else {
      // «Назад» на подборе появляется, когда подбор не вышел (сервера нет).
      let появилась = false;
      try {
        await п.waitForSelector('#подбор-назад:not(.скрыт)', { timeout: 6000 });
        появилась = true;
      } catch (сбой) { появилась = false; }
      проверить(появилась, метка + ': без сервера на подборе появилась кнопка «Назад»');
      if (!появилась) return;
      await нажатьУзел(п, '#подбор-назад', 'кнопка «Назад» на подборе', true);
    }

    const столыСнова = await дождатьсяЭкрана(п, 'экран-открытые-столы', 4000);
    проверить(столыСнова, метка + ': с подбора вернулись на список столов, не в лобби и не в пустоту');
    if (!столыСнова) return;

    if (какВыйтиСоСтолов === 'кнопка') await нажатьУзел(п, '#открытые-столы-назад', 'Назад на списке столов', true);
    else await нажатьСтрелку(п);
    if (!await вернулисьВЛобби(п, метка + ': со столов (после подбора) вернулись в лобби')) return;
    await стрелкаУводитНаВитрину(п, метка);
    проверить(н.красные.length === 0, метка + ': консоль чистая' + (н.красные.length ? ': ' + н.красные.join(' | ') : ''));
  } finally { await н.контекст.close(); }
}

/** Д: три круга столов подряд, разные выходы, потом стрелка на лобби. */
async function сценарийД(браузер) {
  const н = await открытьЛобби(браузер, 'Д. три круга «Найти игру» подряд, потом стрелка на лобби');
  try {
    if (!н.лобби) return;
    const п = н.страница;
    for (let круг = 1; круг <= 3; круг++) {
      if (!await войтиВСтолы(п, 'Д, круг ' + круг)) return;
      if (круг % 2) await нажатьУзел(п, '#открытые-столы-назад', 'Назад на списке столов', true);
      else await нажатьСтрелку(п);
      if (!await вернулисьВЛобби(п, 'Д, круг ' + круг + ': вернулись в лобби')) return;
    }
    await стрелкаУводитНаВитрину(п, 'Д');
    проверить(н.красные.length === 0, 'Д: консоль чистая' + (н.красные.length ? ': ' + н.красные.join(' | ') : ''));
  } finally { await н.контекст.close(); }
}

