'use strict';

/* =====================================================================
   ПРОВЕРКА: переспрос длинного опроса при сворачивании страницы.

   Что здесь проверяется (js/сеть.js, около строк 2190–2270).
   Страница следит за скрытостью (document.hidden и события Telegram
   activated/deactivated). Когда признак меняется, висящий длинный опрос
   «/что-нового» обрывается через AbortController (ручка.прервать) и сразу
   уходит новый опрос — уже с правильным полем «скрыта» в теле. Строка
   «связь потеряна» при этом появляться не должна: это не обрыв связи,
   а переспрос с уже другим признаком.

   Как проверяем без браузера. Поднимаем js/сеть.js в песочнице vm
   (используя помощники из tests/поддельный-браузер.js — документ, память,
   запуск в контексте), но сеть подделываем сами: fetch на «/что-нового»
   висит, пока его не оборвут через signal, и записывает тела запросов;
   fetch на «/создать» и «/ход» отвечает сразу. AbortController в стандартной
   песочнице не заведён (это вещь браузера/Node, не входит в набор
   поддельного окна) — добавляем свой, СЧИТАЮЩИЙ отдельно «сколько раз код
   позвал abort()» и «сработал ли обрыв по-настоящему» (настоящий
   AbortController второй раз не срабатывает — это и есть честная модель).

   Запуск: node tests/переспрос-при-сворачивании.js
   Ломающий запуск: node tests/переспрос-при-сворачивании.js --сломать
     — в памяти убирает часть проверки «ручка.переспросить» (строка около
     2227), которая как раз и не даёт дважды прерывать один и тот же
     висящий опрос при двух событиях подряд.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const { поднять, сделатьДокумент, сделатьПамять } = require('./поддельный-браузер.js');

const КОРЕНЬ = path.join(__dirname, '..');
const ПУТЬ_СЕТЬ = path.join(КОРЕНЬ, 'js', 'сеть.js');

const ломать = process.argv.indexOf('--сломать') !== -1;

/* ---------------------------------------------------------------------
   Порча: убрать в памяти проверку «ручка.переспросить» из скрытостьСменилась.
   Строка ищется дословно — не нашлась, значит сеть.js изменился и порчу
   надо переписать заново (тест обязан упасть с понятной причиной, а не
   молча ничего не поломать).
   --------------------------------------------------------------------- */
function испортить(исходник) {
  const было = 'if (!опросИдёт || !ручка || !ручка.прервать || ручка.переспросить) return;';
  const стало = 'if (!опросИдёт || !ручка || !ручка.прервать) return;';
  if (исходник.indexOf(было) === -1) {
    throw new Error('строка для порчи не найдена в js/сеть.js — проверку --сломать надо обновить');
  }
  return исходник.split(было).join(стало);
}

/* ---------------------------------------------------------------------
   Свой AbortController для песочницы: браузерных «абортеров» в vm нет.
   Идемпотентен, как настоящий (второй abort() ничего не меняет в signal
   и слушателей не зовёт второй раз) — но ДОПОЛНИТЕЛЬНО считает, сколько
   раз код вообще позвал abort(), чтобы поймать лишний, ненужный вызов.
   --------------------------------------------------------------------- */
function сделатьAbortController() {
  return class ПоддельныйAbortController {
    constructor() {
      const слушатели = [];
      let сработал = false;
      this.вызовов = 0;
      this.сработал = false;
      this.signal = {
        aborted: false,
        addEventListener: function (имя, дело) { if (имя === 'abort') слушатели.push(дело); },
        removeEventListener: function () {},
        _controller: this
      };
      const self = this;
      this.signal._controller = self;
      this.abort = function () {
        self.вызовов++;
        if (сработал) return;                 // настоящий AbortController второй раз молчит
        сработал = true;
        self.сработал = true;
        self.signal.aborted = true;
        for (const д of слушатели.slice()) д();
      };
    }
  };
}

/* ---------------------------------------------------------------------
   Путь из полного адреса запроса: «http://127.0.0.1:8790/что-нового» → «/что-нового».
   --------------------------------------------------------------------- */
function путьИзАдреса(url) {
  const м = String(url).match(/^https?:\/\/[^/]+(\/.*)$/);
  return м ? м[1] : String(url);
}

function запуститьПроверку() {
  const исходникИсходный = fs.readFileSync(ПУТЬ_СЕТЬ, 'utf8');
  const исходник = ломать ? испортить(исходникИсходный) : исходникИсходный;

  const проверки = [];
  function проверить(условие, текст) {
    проверки.push({ ок: Boolean(условие), текст: текст });
  }

  const журналОпроса = [];   // { тело, controller } — по одной записи на каждый /что-нового
  const журналХода = [];     // { тело } — на каждый /ход
  const телеграмСобытия = {};

  function firedTelegram(имя) {
    (телеграмСобытия[имя] || []).forEach(function (cb) { cb(); });
  }

  function fakeFetch(url, settings) {
    const путь = путьИзАдреса(url);
    const тело = JSON.parse((settings && settings.body) || '{}');

    if (путь === '/создать') {
      return Promise.resolve({
        ok: true, status: 200,
        json: function () { return Promise.resolve({ ок: true, код: 'AAAA', пропуск: 'ppp', состояние: null }); }
      });
    }

    if (путь === '/что-нового') {
      const controller = settings && settings.signal ? settings.signal._controller : null;
      журналОпроса.push({ тело: тело, controller: controller });
      return new Promise(function (готово, отказ) {
        if (settings && settings.signal) {
          settings.signal.addEventListener('abort', function () {
            const ошибка = new Error('aborted');
            ошибка.name = 'AbortError';
            отказ(ошибка);
          });
        }
        // иначе висит вечно — ровно то, что и нужно длинному опросу
      });
    }

    if (путь === '/ход') {
      журналХода.push({ тело: тело });
      return Promise.resolve({
        ok: true, status: 200,
        json: function () { return Promise.resolve({ ок: true, данные: {} }); }
      });
    }

    // прочие пути этому тесту не нужны — отвечаем тихим «ничего»
    return Promise.resolve({ ok: true, status: 200, json: function () { return Promise.resolve({}); } });
  }

  const жСвязь = [];   // показатьСвязь(текст, вид) — на случай если строку всё же покажут

  const рез = поднять(исходник, {
    документ: сделатьДокумент(),
    память: сделатьПамять(false),
    telegram: {
      onEvent: function (имя, дело) { (телеграмСобытия[имя] = телеграмСобытия[имя] || []).push(дело); },
      offEvent: function () {},
      isActive: true
    },
    fetch: fakeFetch,
    размер: { ширина: 390, высота: 844 },
    имяФайла: 'js/сеть.js'
  });

  // AbortController — добавляем в готовую песочницу (используется только
  // позже, во время запросов, а не при разборе файла).
  рез.песочница.AbortController = сделатьAbortController();

  // Мост к игре: js/сеть.js сам не рисует стол, зовёт window.ИграПоСети.
  рез.окно.ИграПоСети = {
    начать: function () {},
    экран: function () {},
    показатьСвязь: function (текст, вид) { жСвязь.push({ текст: текст, вид: вид }); }
  };

  const пауза = function (мс) { return new Promise(function (r) { setTimeout(r, мс || 0); }); };

  return (async function () {
    let ошибкаВыполнения = null;
    try {
      // ---- Вход в комнату: первый опрос уходит с текущим признаком (видимая страница) ----
      const итогСоздания = await рез.спросить("window.Сеть.создатьКомнату({мест:2, переводной:false, парами:false})");
      проверить(итогСоздания && итогСоздания.ок === true, 'комната создалась (фальшивый /создать ответил как надо)');
      await пауза(10);
      проверить(журналОпроса.length === 1, 'после входа в комнату сразу ушёл ровно один опрос «что нового»');
      if (журналОпроса[0]) {
        проверить(журналОпроса[0].тело.скрыта === false, 'первый опрос несёт скрыта:false — страница видима');
      }

      // ---- Проверка 1: одиночное сворачивание ----
      рез.документ.hidden = true;
      рез.документ.visibilityState = 'hidden';
      рез.документ.dispatchEvent('visibilitychange');
      await пауза(20);

      проверить(журналОпроса.length === 2, 'сверка 1: после сворачивания ушёл ровно один новый опрос');
      if (журналОпроса[1]) проверить(журналОпроса[1].тело.скрыта === true, 'сверка 1: новый опрос несёт скрыта:true');
      if (журналОпроса[0] && журналОпроса[0].controller) {
        проверить(журналОпроса[0].controller.вызовов === 1, 'сверка 1: старый опрос прерван ровно один раз');
      }

      // Связь потеряна быть не должно: проверяем через отправитьХод —
      // приватного «связьЕсть» снаружи не видно, но ход, отправленный
      // сразу после смены признака, не должен получить отказ «связь потеряна».
      const ходПосле1 = await рез.спросить('window.Сеть.отправитьХод({})');
      const причина1 = (ходПосле1 && ходПосле1.причина) ? String(ходПосле1.причина) : '';
      проверить(причина1.indexOf('отеряна') === -1 && !(ходПосле1 && ходПосле1.ошибкаСвязи),
        'после одиночного сворачивания ход не отказан по причине «связь потеряна»');

      // ---- Проверка 3: разворачивание (hidden=false + Telegram activated) ----
      рез.документ.hidden = false;
      рез.документ.visibilityState = 'visible';
      firedTelegram('activated');
      await пауза(20);

      проверить(журналОпроса.length === 3, 'сверка 3: после разворачивания ушёл ровно один новый опрос');
      if (журналОпроса[2]) проверить(журналОпроса[2].тело.скрыта === false, 'сверка 3: новый опрос несёт скрыта:false');
      if (журналОпроса[1] && журналОпроса[1].controller) {
        проверить(журналОпроса[1].controller.вызовов === 1, 'сверка 3: предыдущий опрос прерван ровно один раз');
      }

      // ---- Проверка 5: событие без смены признака — обрыва быть не должно ----
      firedTelegram('activated');   // страница и так уже видима и активна
      await пауза(20);

      проверить(журналОпроса.length === 3, 'сверка 5: повторный activated без смены признака нового опроса не начал');
      if (журналОпроса[2] && журналОпроса[2].controller) {
        проверить(журналОпроса[2].controller.вызовов === 0, 'сверка 5: повторный activated не прервал висящий опрос');
      }

      // ---- Проверка 2: пара событий подряд про скрытие — обрыв должен быть один ----
      рез.документ.hidden = true;
      рез.документ.visibilityState = 'hidden';
      рез.документ.dispatchEvent('visibilitychange');   // событие 1: про скрытие
      firedTelegram('deactivated');                       // событие 2 сразу следом: тоже про скрытие
      await пауза(20);

      проверить(журналОпроса.length === 4, 'сверка 2: пара событий про скрытие подряд — новый опрос всего один');
      if (журналОпроса[3]) проверить(журналОпроса[3].тело.скрыта === true, 'сверка 2: новый опрос несёт скрыта:true');
      if (журналОпроса[2] && журналОпроса[2].controller) {
        проверить(журналОпроса[2].controller.вызовов === 1,
          'сверка 2: висящий опрос прерван РОВНО ОДИН раз, а не дважды на два события');
      }

      const ходПосле2 = await рез.спросить('window.Сеть.отправитьХод({})');
      const причина2 = (ходПосле2 && ходПосле2.причина) ? String(ходПосле2.причина) : '';
      проверить(причина2.indexOf('отеряна') === -1 && !(ходПосле2 && ходПосле2.ошибкаСвязи),
        'после пары событий подряд ход не отказан по причине «связь потеряна»');

      // ---- Строка «связь потеряна» ни разу не должна была появиться ----
      const показанаПотеряна = жСвязь.some(function (з) { return String(з.текст || '').indexOf('отеряна') !== -1; });
      проверить(!показанаПотеряна, 'строка «связь потеряна» ни разу не показана за весь сценарий');

      // ---- Консоль песочницы чистая ----
      проверить(рез.ошибкиКонсоли.length === 0,
        'ошибок в консоли нет' + (рез.ошибкиКонсоли.length ? ': ' + рез.ошибкиКонсоли.join(' | ') : ''));

      // ---- Проверка на «ноль событий»: подписка и события правда сработали ----
      проверить(Boolean(телеграмСобытия.activated && телеграмСобытия.activated.length) &&
                Boolean(телеграмСобытия.deactivated && телеграмСобытия.deactivated.length),
        'подписки на Telegram activated/deactivated поставлены и реально сработали');
      проверить(журналОпроса.length >= 4 && журналХода.length >= 2,
        'за сценарий прошло заметное число запросов — проверка не «провалилась в тишину»');

    } catch (сбой) {
      ошибкаВыполнения = сбой;
    }

    if (ошибкаВыполнения) {
      проверить(false, 'сценарий упал с ошибкой: ' + (ошибкаВыполнения && ошибкаВыполнения.stack || ошибкаВыполнения));
    }

    const провалы = проверки.filter(function (п) { return !п.ок; });
    console.log((ломать ? '[--сломать] ' : '') + 'Переспрос при сворачивании:');
    for (const п of проверки) {
      console.log((п.ок ? '  ок   ' : '  ПЛОХО ') + п.текст);
    }
    console.log('Итого проверок: ' + проверки.length + ', провалов: ' + провалы.length);
    process.exit(провалы.length ? 1 : 0);
  })();
}

запуститьПроверку();
