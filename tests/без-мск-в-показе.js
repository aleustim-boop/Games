'use strict';

/* =====================================================================
   Игрок нигде не видит «МСК», «по Москве», «московское время», «Moscow».
   Решение владельца 06.10: в игре время по часам устройства без названия
   пояса, в письмах бота — по Киеву.

   Что проверяет (чистый node, без браузера):
     А) в index.html, игры/дурак/game.js, общее/js/турнир-экран.js, общее/js/языки.js и в
        server/возврат-ушедших.js нет этих слов в том, что видит игрок:
        в разметке и в строковых литералах (комментарии не в счёт);
     Б) текст письма на миг 17:00 UTC: летом «20:00 по Киеву», зимой
        «19:00 по Киеву»;
     В) подпись экрана турнира для пояса +120 минут и мига 17:00 UTC —
        «19:00», без букв пояса.

   Запуск:
       node tests/без-мск-в-показе.js              — проект
       node tests/без-мск-в-показе.js <папка>      — файлы берутся из папки
         (она устроена как проект: index.html, js/…, server/…)
       node tests/без-мск-в-показе.js --сломать    — ломающий запуск: сам делает
         КОПИИ во временной папке, портит их тремя способами и требует, чтобы
         каждая порча покраснела (выход 3, если хоть одна не покраснела).
   Итог — строкой «Итого проверок: N, провалов: M».
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const корень = path.join(__dirname, '..');
const ФАЙЛЫ = ['index.html', 'игры/дурак/game.js', 'общее/js/турнир-экран.js', 'общее/js/языки.js', 'server/возврат-ушедших.js'];
// Файлы, без которых копия не загрузится (возврат-ушедших их требует).
const ФАЙЛЫ_КОПИИ = ФАЙЛЫ.concat(['server/папка-данных.js']);
// Без \b: он не знает кириллицы.
const ЗАПРЕТНОЕ = /МСК|по Москве|московск|Moscow/i;

let всего = 0;
let провалов = 0;
function надо(условие, имя, подробность) {
  всего++;
  if (!условие) {
    провалов++;
    console.log('ПЛОХО ' + имя + (подробность ? ' — ' + подробность : ''));
  } else {
    console.log('ок    ' + имя);
  }
}

/** Что видит игрок в html: всё, кроме комментариев. */
function видимоеВHtml(текст) {
  return text_без(текст, /<!--[\s\S]*?-->/g);
}
function text_без(текст, шаблон) {
  return текст.replace(шаблон, '');
}

/**
 * Строковые литералы js ('…', "…", `…`) — без комментариев. Небольшой
 * сканер состояний: достаточно для наших файлов, ноль найденного — провал.
 */
function литералыJs(текст) {
  const итог = [];
  let i = 0;
  while (i < текст.length) {
    const с = текст[i];
    const следующий = текст[i + 1];
    if (с === '/' && следующий === '/') {
      while (i < текст.length && текст[i] !== '\n') i++;
    } else if (с === '/' && следующий === '*') {
      const конец = текст.indexOf('*/', i + 2);
      i = конец === -1 ? текст.length : конец + 2;
    } else if (с === '\'' || с === '"' || с === '`') {
      let j = i + 1;
      while (j < текст.length && текст[j] !== с) {
        if (текст[j] === '\\') j++;
        else if (с !== '`' && текст[j] === '\n') break;   // сбой сканера: не уйти за строку
        j++;
      }
      итог.push(текст.slice(i + 1, j));
      i = j + 1;
    } else {
      i++;
    }
  }
  return итог;
}

function проверитьВсё(база) {
  // А) запретные слова в том, что видит игрок
  for (const файл of ФАЙЛЫ) {
    const полный = path.join(база, файл);
    let текст = '';
    try { текст = fs.readFileSync(полный, 'utf8'); } catch (беда) { текст = ''; }
    надо(текст.length > 0, 'А) файл прочитан: ' + файл);
    if (!текст.length) continue;
    const видимое = файл.endsWith('.html') ? [видимоеВHtml(текст)] : литералыJs(текст);
    надо(видимое.length > 0 && видимое.join('').length > 0, 'А) в файле найдены видимые строки: ' + файл);
    const плохие = видимое.filter(function (с) { return ЗАПРЕТНОЕ.test(с); });
    надо(плохие.length === 0, 'А) нет «МСК/Москве/московск/Moscow» в показе: ' + файл,
      плохие.slice(0, 2).map(function (с) { return с.slice(0, 80); }).join(' | '));
  }

  // Б) письмо по Киеву, летом и зимой
  let письмо = null;
  try { письмо = require(path.join(база, 'server', 'возврат-ушедших.js')); } catch (беда) { письмо = null; }
  надо(!!письмо && typeof письмо.текстПисьма === 'function', 'Б) возврат-ушедших.js загружается и отдаёт текстПисьма');
  if (письмо && typeof письмо.текстПисьма === 'function') {
    const лето = письмо.текстПисьма('3дня', { игра: 'дурак', началоМс: Date.UTC(2026, 6, 15, 17, 0) });
    const зима = письмо.текстПисьма('3дня', { игра: 'дурак', началоМс: Date.UTC(2027, 0, 15, 17, 0) });
    const зима2 = письмо.текстПисьма('14дней', { игра: 'дурак', началоМс: Date.UTC(2027, 0, 15, 17, 0) });
    надо(лето.indexOf('Сегодня в 20:00 по Киеву') !== -1, 'Б) летом 17:00 UTC → «20:00 по Киеву»', лето);
    надо(зима.indexOf('Сегодня в 19:00 по Киеву') !== -1, 'Б) зимой 17:00 UTC → «19:00 по Киеву»', зима);
    надо(зима2.indexOf('Сегодня в 19:00 по Киеву') !== -1, 'Б) второе письмо зимой → «19:00 по Киеву»', зима2);
  }

  // В) подпись экрана турнира в поясе +120
  let Экран = null;
  try { Экран = require(path.join(база, 'общее', 'js', 'турнир-экран.js')); } catch (беда) { Экран = null; }
  надо(!!Экран && typeof Экран.модель === 'function', 'В) турнир-экран.js загружается и отдаёт модель');
  if (Экран && typeof Экран.модель === 'function') {
    const начало = Date.UTC(2026, 9, 5, 17, 0);
    const вид = { ид: 'дурак-2026-10-05', игра: 'дурак', началоМс: начало, конецМс: начало + 1800000,
      состояние: 'запись', записалось: 0, записан: false, таблица: [] };
    const м = Экран.модель(вид, начало - 3600000, 120);
    надо(м.время === '19:00', 'В) пояс +120, 17:00 UTC → «19:00»', String(м.время));
    надо(!/[A-Za-zА-Яа-яЁё]/.test(String(м.время)), 'В) в подписи времени нет букв пояса', String(м.время));
  }
}

function сломатьИПроверить() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'без-мск-'));
  for (const файл of ФАЙЛЫ_КОПИИ) {
    const куда = path.join(папка, файл);
    fs.mkdirSync(path.dirname(куда), { recursive: true });
    fs.copyFileSync(path.join(корень, файл), куда);
  }
  const порчи = [
    ['МСК в разметке', 'index.html', 'Каждый день в 20:00', 'Каждый день в 20:00 МСК'],
    ['«по Москве» в письме', 'server/возврат-ушедших.js', "' по Киеву — ' + названиеТурнира(турнир.игра) + ', можно", "' по Москве — ' + названиеТурнира(турнир.игра) + ', можно"],
    ['МСК в подписи экрана', 'общее/js/турнир-экран.js', 'return времяВПоясе(началоМс, поясМин);', "return времяВПоясе(началоМс, поясМин) + ' МСК';"]
  ];
  let непокрасневших = 0;
  for (const [имя, файл, было, стало] of порчи) {
    const путь = path.join(папка, файл);
    const исходный = fs.readFileSync(путь, 'utf8');
    if (исходный.indexOf(было) === -1) {
      console.log('Порча «' + имя + '»: НЕ применилась (строка не найдена) — плохо');
      непокрасневших++;
      continue;
    }
    fs.writeFileSync(путь, исходный.replace(было, стало));
    const р = spawnSync(process.execPath, [__filename, папка], { encoding: 'utf8' });
    const строкаИтога = (р.stdout || '').trim().split('\n').pop();
    if (р.status === 1) console.log('Порча «' + имя + '»: покраснела — хорошо (' + строкаИтога + ')');
    else { console.log('Порча «' + имя + '»: НЕ покраснела (выход ' + р.status + ') — проверка украшение'); непокрасневших++; }
    fs.writeFileSync(путь, исходный);   // возвращаем в копии, чтобы порчи не копились
  }
  console.log('Копии лежали в ' + папка);
  process.exit(непокрасневших ? 3 : 0);
}

if (process.argv[2] === '--сломать') {
  сломатьИПроверить();
} else {
  const база = process.argv[2] ? path.resolve(process.argv[2]) : корень;
  проверитьВсё(база);
  console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
}
