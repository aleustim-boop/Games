/** Каждая плитка «.плитка-игры» в порядке разметки: игра, вид фильтра, выключена ли. */
function плиткиИзРазметки() {
  const html = fs.readFileSync(path.join(КОРЕНЬ, 'index.html'), 'utf8');
  const теги = html.match(/<(?:a|button)\s[^>]*class="плитка-игры"[^>]*>/g) || [];
  return теги.map(function (тег) {
    const игра = (тег.match(/data-игра="([^"]+)"/) || [])[1] || '';
    const вид = (тег.match(/data-вид="([^"]+)"/) || [])[1] || '';
    const disabled = /\bdisabled\b/.test(тег);
    return { игра: игра, вид: вид, disabled: disabled };
  });
}

