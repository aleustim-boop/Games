/**
 * ОЖИДАЕМЫЙ ФОН ОКНА — ЖИВЬЁМ ИЗ ТЕХ ЖЕ ФАЙЛОВ, ЧТО КРАСЯТ СТРАНИЦУ.
 * Переменная «--сб-фон» объявлена в «:root» сразу в нескольких файлах
 * оформления (style.css и style-коллекция.css). Каскад CSS при равной
 * специфичности отдаёт победу тому объявлению, чей <link> в index.html
 * подключён ПОСЛЕДНИМ — значит и проверка обязана смотреть на порядок
 * <link> в index.html, а не хранить число сама.
 */
function ожидаемыйФонОкна() {
  const html = fs.readFileSync(path.join(КОРЕНЬ, 'index.html'), 'utf8');
  const файлы = (html.match(/<link[^>]+rel="stylesheet"[^>]+href="([^"?"]+\.css)[^"]*"/g) || [])
    .map(function (тег) { return (тег.match(/href="([^"?"]+\.css)/) || [])[1]; })
    .filter(Boolean);
  let найденный = null;
  for (const имя of файлы) {
    const полныйПуть = path.join(КОРЕНЬ, имя);
    if (!fs.existsSync(полныйПуть)) continue;
    const текст = fs.readFileSync(полныйПуть, 'utf8');
    const совпадения = текст.match(/--сб-фон\s*:\s*(#[0-9a-fA-F]{3,8})\s*;/g) || [];
    if (совпадения.length === 0) continue;
    const последнее = совпадения[совпадения.length - 1];
    найденный = (последнее.match(/(#[0-9a-fA-F]{3,8})/) || [])[1] || найденный;
  }
  if (!найденный) {
    throw new Error('ОЖИДАЕМЫЙ ФОН ОКНА: ни в одном подключённом <link> из index.html ' +
      'не нашлась переменная «--сб-фон» — оформление изменилось сильнее, чем ждал ' +
      'этот тест, обновите чтение.');
  }
  return найденный.toLowerCase();
}

