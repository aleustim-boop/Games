'use strict';

/* =====================================================================
   СВОДНАЯ ПРОВЕРКА «ЖИВЫХ ЛОББИ» (этап Э9).
   Запускает по очереди все node-проверки Э1–Э8 дочерними процессами,
   печатает имя, код выхода и последнюю строку вывода, затем итог.
   Браузерные проверки (где есть playwright/chromium) сюда не входят.
   Ноль найденных проверок или любой ненулевой код — провал.

   Запуск:   node tests/живые-лобби-итог.js
   Ломающий: node tests/живые-лобби-итог.js --сломать
     (в список добавляются падающая и несуществующая проверки из
      временной папки — сводная обязана покраснеть)
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const ЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;

const ИМЕНА = [
  'личины-лобби-функции.js',
  'личины-подбор.js',
  'стол-личин-сервер.js',
  'живые-лобби.js',
  'живые-лобби-сервер.js',
  'голос-личин.js',
  'обучение-личин.js',
  'рейтинг-личин.js',
  'открытые-столы-сервер.js',
  'открытые-столы-портреты.js'
];

const список = [];
for (const имя of ИМЕНА) {
  const путь = path.join(__dirname, имя);
  if (!fs.existsSync(путь)) { список.push({ имя, путь, нет: true }); continue; }
  const текст = fs.readFileSync(путь, 'utf8');
  if (/playwright|chromium/i.test(текст)) { console.log('пропуск (браузерная): ' + имя); continue; }
  список.push({ имя, путь });
}

if (ЛОМАТЬ) {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'лобби-итог-'));
  const падает = path.join(папка, 'падающая.js');
  fs.writeFileSync(падает, 'console.log("нарочно упала"); process.exit(1);\n');
  список.push({ имя: 'падающая.js', путь: падает });
  список.push({ имя: 'несуществующая.js', путь: path.join(папка, 'нет-такой.js'), нет: true });
}

let провалов = 0;
if (список.length === 0) { console.log('ПРОВАЛ: не найдено ни одной проверки'); провалов++; }

for (const п of список) {
  if (п.нет) { console.log('ПРОВАЛ  ' + п.имя + '  файла нет'); провалов++; continue; }
  const р = spawnSync(process.execPath, [п.путь], { cwd: КОРЕНЬ, encoding: 'utf8', timeout: 300000, maxBuffer: 64 * 1024 * 1024 });
  const код = р.status === null ? 'сбой/таймаут' : р.status;
  const строки = ((р.stdout || '') + (р.stderr || '')).split(/\r?\n/).filter(function (с) { return с.trim(); });
  const последняя = строки.length ? строки[строки.length - 1] : '(вывода нет)';
  const ок = код === 0;
  if (!ок) провалов++;
  console.log((ок ? 'ОК      ' : 'ПРОВАЛ  ') + п.имя + '  код ' + код + '  | ' + последняя);
}

console.log('Итого проверок: ' + список.length + ', провалов: ' + провалов);
process.exit(провалов ? 1 : 0);
