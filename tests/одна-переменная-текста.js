function экранироватьRegExp(текст) {
  return текст.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/** Значение переменной ровно так, как записано в файле — без второй,
 *  вручную вписанной копии внутри проверки. */
function читатьПеременную(текстCSS, имя) {
  const рег = new RegExp(экранироватьRegExp(имя) + '\\s*:\\s*([^;]+);');
  const совпадение = текстCSS.match(рег);
  if (!совпадение) {
    throw new Error('переменная «' + имя + '» не нашлась — приём объявления поменялся, обновите эту проверку');
  }
  return совпадение[1].trim();
}

/** Сколько раз переменная реально ОБЪЯВЛЕНА (имя: #цвет;) в тексте CSS —
 *  считаем только настоящие объявления значения, не упоминания в
 *  комментариях (у тех после имени в кавычках нет «: #...;»). */
function посчитатьОбъявления(текстCSS, имя) {
  const рег = new RegExp(экранироватьRegExp(имя) + '\\s*:\\s*#[0-9a-fA-F]{3,8}\\s*;', 'g');
  const совпадения = текстCSS.match(рег);
  return совпадения ? совпадения.length : 0;
}

function свободныйПорт() {
  return new Promise((готово, брак) => {
    const проба = http.createServer();
    проба.on('error', брак);
    проба.listen(0, АДРЕС_ХОЗЯИНА, () => {
      const порт = проба.address().port;
      проба.close(() => готово(порт));
    });
  });
}

async function выбратьСвободныйПорт() {
  for (let попытка = 0; попытка < 6; попытка++) {
    const порт = await свободныйПорт();
    if (ЗАПРЕЩЁННЫЕ_ПОРТЫ.indexOf(порт) === -1) return порт;
  }
  throw new Error('не удалось получить свободный порт, отличный от боевых 8790/8791');
}

const ТИПЫ_ФАЙЛОВ = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.woff2': 'font/woff2'
};

function запрещённыйАдрес(адрес) {
  const низ = адрес.toLowerCase();
  if (низ.indexOf('.env') !== -1) return true;
  const части = низ.split(/[\\/]/).filter(Boolean);
  if (части.length && части[0] === 'bot') return true;
  return части.some((часть) => часть.charAt(0) === '.');
}

/** Свой статический сервер, раздающий папку проекта. Своя копия на
 *  свободном порту (не 8790/8791) — боевой сервер комнат не трогаем. */
function поднятьСервер(порт) {
  return new Promise((готово) => {
    const сервер = http.createServer((запрос, ответ) => {
      let адрес;
      try {
        адрес = decodeURIComponent(запрос.url.split('?')[0]);
      } catch (ошибка) {
        ответ.writeHead(400); ответ.end('непонятный адрес'); return;
      }
      if (адрес === '/') адрес = '/index.html';
      if (запрещённыйАдрес(адрес)) { ответ.writeHead(403); ответ.end('доступ закрыт'); return; }

      const относительный = адрес.replace(/^\/+/, '');
      const файл = path.join(КОРЕНЬ, относительный);
      if (файл !== КОРЕНЬ && !файл.startsWith(КОРЕНЬ + path.sep)) {
        ответ.writeHead(403); ответ.end('доступ закрыт: файл вне папки проекта'); return;
      }

      fs.readFile(файл, (ошибка, данные) => {
        if (ошибка) { ответ.writeHead(404); ответ.end('не найдено: ' + адрес); return; }
        ответ.writeHead(200, {
          'Content-Type': ТИПЫ_ФАЙЛОВ[path.extname(файл).toLowerCase()] || 'application/octet-stream',
          'Cache-Control': 'no-store'
        });
        ответ.end(данные);
      });
    });
    сервер.listen(порт, АДРЕС_ХОЗЯИНА, () => готово(сервер));
  });
}

/* ---------------------------------------------------------------------
   Чистый прогон: считает объявления в настоящих файлах, поднимает
   свой сервер, браузером обходит восемь страниц, сверяет корневую
   переменную и цвет узлов с ОЖИДАЕМЫМИ.
   --------------------------------------------------------------------- */

async function чистыйПрогон() {
  const строки = [];
  let провалов = 0;
  function проверить(имя, условие, детали) {
    строки.push((условие ? '  ок    — ' : '  ПЛОХО — ') + имя + (детали ? ' (' + детали + ')' : ''));
    if (!условие) провалов++;
  }

  const текстStyle = fs.readFileSync(ПУТЬ_STYLE, 'utf8');
  const текстКоллекция = fs.readFileSync(ПУТЬ_КОЛЛЕКЦИЯ, 'utf8');

  /* А) ровно одно объявление суммарно на оба файла. */
  const объявленийStyle = посчитатьОбъявления(текстStyle, ИМЯ_ПЕРЕМЕННОЙ);
  const объявленийКоллекция = посчитатьОбъявления(текстКоллекция, ИМЯ_ПЕРЕМЕННОЙ);
  const объявленийВсего = объявленийStyle + объявленийКоллекция;
  проверить(
    'объявление «' + ИМЯ_ПЕРЕМЕННОЙ + '» ровно одно на оба файла',
    объявленийВсего === 1,
    'style.css: ' + объявленийStyle + ', style-коллекция.css: ' + объявленийКоллекция
  );

  /* Ожидаемое значение — читаем из настоящего style.css, а не пишем
     вручную вторую копию числа. */
  const ожидаемоеЗначение = читатьПеременную(текстStyle, ИМЯ_ПЕРЕМЕННОЙ);

  const порт = await выбратьСвободныйПорт();
  const сервер = await поднятьСервер(порт);
  console.log('  [чисто] свой сервер на http://' + АДРЕС_ХОЗЯИНА + ':' + порт + '/');

  let браузер = null;
  try {
    браузер = await chromium.launch();
    for (const имя of СТРАНИЦЫ) {
      const страница = await браузер.newPage();
      await безTelegram(страница);
      await страница.goto('http://' + АДРЕС_ХОЗЯИНА + ':' + порт + '/' + имя, { waitUntil: 'load' });
      await страница.waitForTimeout(150);

      const реальноеЗначение = await страница.evaluate(() =>
        getComputedStyle(document.documentElement).getPropertyValue('--сб-текст').trim()
      );
      проверить(
        имя + ': корневая «' + ИМЯ_ПЕРЕМЕННОЙ + '» равна значению из style.css',
        реальноеЗначение === ожидаемоеЗначение,
        'ожидали «' + ожидаемоеЗначение + '», получили «' + реальноеЗначение + '»'
      );

      const ожидаемыеУзлы = ОЖИДАЕМЫЕ_УЗЛЫ[имя] || [];
      if (ожидаемыеУзлы.length === 0) {
        проверить(имя + ': есть записанные ожидаемые узлы для сравнения', false, 'список пуст — проверка ничего не нашла бы');
      }
      for (const узел of ожидаемыеУзлы) {
        const цвет = await страница.evaluate((селектор) => {
          const эл = document.querySelector(селектор);
          return эл ? getComputedStyle(эл).color : null;
        }, узел.селектор);
        проверить(
          имя + ': цвет узла «' + узел.селектор + '»',
          цвет === узел.цвет,
          'ожидали «' + узел.цвет + '», получили «' + цвет + '»'
        );
      }

      await страница.close();
    }
  } finally {
    if (браузер) await браузер.close();
    сервер.close();
  }

  return { строки, провалов };
}

/* ---------------------------------------------------------------------
   Ломающий прогон (--сломать): портит КОПИЮ style-коллекция.css во
   временной папке — второе объявление «--сб-текст» с другим цветом —
   и требует, чтобы пункт «А» (счётчик объявлений) это поймал.
   --------------------------------------------------------------------- */

function ломающийПрогон() {
  const оригиналКоллекции = fs.readFileSync(ПУТЬ_КОЛЛЕКЦИЯ, 'utf8');
  const временнаяПапка = fs.mkdtempSync(path.join(os.tmpdir(), 'одна-переменная-сломано-'));
  const копияКоллекции = path.join(временнаяПапка, 'style-коллекция.css');

  /* Дописываем второе объявление сразу после открывающей «:root {» —
     ровно то, от чего избавились правкой: второй источник цвета текста. */
  const испорченныйТекст = оригиналКоллекции.replace(
    /:root\s*\{/,
    ':root {\n  --сб-текст: #123456; /* испорчено ломающим запуском */'
  );
  if (испорченныйТекст === оригиналКоллекции) {
    console.log('Итого проверок: 1, провалов: 1');
    console.log('  ПЛОХО — не удалось вставить порчу: в копии style-коллекция.css не нашёлся «:root {»');
    process.exit(1);
  }
  fs.writeFileSync(копияКоллекции, испорченныйТекст, 'utf8');
  console.log('  порченая копия: ' + копияКоллекции + ' (настоящий style-коллекция.css не тронут)');

  const текстStyle = fs.readFileSync(ПУТЬ_STYLE, 'utf8');
  const текстКоллекцииПорченый = fs.readFileSync(копияКоллекции, 'utf8');

  const объявленийStyle = посчитатьОбъявления(текстStyle, ИМЯ_ПЕРЕМЕННОЙ);
  const объявленийКоллекция = посчитатьОбъявления(текстКоллекцииПорченый, ИМЯ_ПЕРЕМЕННОЙ);
  const объявленийВсего = объявленийStyle + объявленийКоллекция;

  const условиеПоймано = объявленийВсего !== 1;
  console.log('  [' + (условиеПоймано ? 'ок' : 'ПЛОХО') + '] счётчик объявлений на порченой копии: ' +
    объявленийВсего + ' (style.css: ' + объявленийStyle + ', порченая коллекция: ' + объявленийКоллекция + ')');

  if (условиеПоймано) {
    console.log('ИТОГ ЛОМАЮЩЕГО ПРОГОНА: порча поймана точно — счётчик объявлений увидел два вместо одного.');
    process.exit(0);
  } else {
    console.log('ИТОГ ЛОМАЮЩЕГО ПРОГОНА: ПРОВЕРКА НЕТОЧНАЯ — порченая копия со вторым объявлением прошла как чистая.');
    process.exit(1);
  }
}

/* ---------------------------------------------------------------------
   Точка входа
   --------------------------------------------------------------------- */

(async () => {
  if (process.argv.indexOf('--сломать') !== -1) {
    ломающийПрогон();
    return;
  }

  const результат = await чистыйПрогон();
  console.log(результат.строки.join('\n'));
  console.log('Итого проверок: ' + результат.строки.length + ', провалов: ' + результат.провалов);
  process.exit(результат.провалов > 0 ? 1 : 0);
})().catch((ошибка) => {
  console.error('НЕОЖИДАННАЯ ОШИБКА: ' + (ошибка && ошибка.stack || ошибка));
  process.exit(2);
});
