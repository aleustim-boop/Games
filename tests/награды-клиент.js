  /* Закрытая память (приватный режим) — не повод падать. */
  const закрытая = бр.сделатьПамять(true);
  const пЗакр = бр.поднять(исходник, {
    имяФайла: 'общее/js/награды.js',
    память: закрытая,
    fetch: function () { return ответОк(ответСервера(1)); },
    telegram: { initData: 'подпись-для-проверки' }
  });
  const приЗакрытой = await пЗакр.окно.Награды.обновить();
  проверить('закрытая память: ответ всё равно принят, ошибок нет',
    приЗакрытой === 1 && пЗакр.ошибкиКонсоли.length === 0 && пЗакр.окно.Награды.есть('значок-друг-1') === true);

  /* ================= Случай 5: подписка на событие ================= */
  let режим = 'удача';
  const п5 = поднять({
    поведение: function () {
      return режим === 'удача' ? ответОк(ответСервера(1)) : Promise.reject(new Error('сеть'));
    }
  });
  let первый = 0;
  let второй = 0;
  const отписатьПервого = п5.окно.Награды.наСобытие(function () { первый += 1; });
  п5.окно.Награды.наСобытие(function () { throw new Error('упавший подписчик'); });
  п5.окно.Награды.наСобытие(function () { второй += 1; });
  await п5.окно.Награды.обновить();
  проверить('событие: на удачный ответ зовутся оба здоровых подписчика (' + первый + ', ' + второй + ')',
    первый === 1 && второй === 1);
  проверить('событие: упавший подписчик не уронил обновить() и не дал ошибок в консоль',
    п5.окно.Награды.сколькоДрузей() === 1 && п5.ошибкиКонсоли.length === 0);
  режим = 'молчание';
  await п5.окно.Награды.обновить();
  проверить('событие: на неудачу не зовётся', первый === 1 && второй === 1);
  режим = 'удача';
  отписатьПервого();
  await п5.окно.Награды.обновить();
  проверить('событие: после отписки первый молчит, второй слышит (' + первый + ', ' + второй + ')',
    первый === 1 && второй === 2);
  проверить('событие: наСобытие не функции не ломается',
    typeof п5.окно.Награды.наСобытие(null) === 'function');

  /* ================= Случай 6: адрес сервера ================= */
  const п6 = поднять({ поведение: function () { return ответОк(ответСервера(1)); } });
