/* --------------------------------------------------------------------
   Ломающий запуск: копия во временной папке, порча — только в копии.
   -------------------------------------------------------------------- */
function испортитьКопию(имяКопии, было, стало, описание) {
  if (исходник.indexOf(было) === -1) {
    console.log('ОШИБКА: приём порчи устарел — в ' + файл + ' не нашлась строка:');
    console.log('  ' + было);
    process.exit(1);
  }
  const папка = довод('--в') || os.tmpdir();
  fs.mkdirSync(папка, { recursive: true });
  файл = path.join(папка, имяКопии);
  исходник = исходник.split(было).join(стало);
  fs.writeFileSync(файл, исходник, 'utf8');
  console.log('Ломающий запуск: порчу КОПИЮ, файл проекта не тронут.');
  console.log('  копия: ' + файл);
  console.log('  порча: ' + описание);
  console.log('');
}

