/* Ломающий запуск: файл грузим из памяти с испорченным местом, под
   настоящим именем в кэше require. Файл проекта не меняется. */
function загрузитьИспорченным(имяФайла, было, стало) {
  const путь = path.join(КОРЕНЬ, 'server', имяФайла);
  let текст = fs.readFileSync(путь, 'utf8');
  if (текст.split(было).length !== 2) { console.log('порча не применилась: ' + имяФайла); process.exit(2); }
  текст = текст.replace(было, стало);
  const м = new Module(путь, module);
  м.filename = путь;
  м.paths = Module._nodeModulePaths(path.dirname(путь));
  м._compile(текст, путь);
  require.cache[путь] = м;
  м.loaded = true;
}
