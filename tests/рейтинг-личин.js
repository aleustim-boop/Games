'use strict';

/* =====================================================================
   РЕЙТИНГ: потолок личин («не выше 4-го места»), этап Э8 «Живых лобби».

   Личина — не человек. Решение В2 (штаб/план-живые-лобби.md): рейтинг
   выглядит живым, но тройка лучших — всегда люди. Личина, которой счёт
   даёт место выше 4-го, показывается ниже людей, не ниже 4-го места;
   людей меньше трёх — сразу после последнего человека (выше человека
   она не бывает). Очки не меняются — только порядок показа.

   Что проверяем (всё в node, без браузера и без сервера):
     1. Три человека + личина с наибольшими очками: личина 4-я в КАЖДОМ
        списке — срез игры, «Все игры», «Друзья» по игре, «Друзья» по
        всем играм и снимок вчерашних мест (файл на диске).
     2. Один человек + личина выше него: личина 2-я везде.
     3. Без личин порядок не меняется (тот же массив, по убыванию очков).
     4. Сама функция опуститьЛичин на разборе случаев (две личины, нет
        людей, личина уже на 4-м, исходный массив не портится).
     Очки личины в строке остаются настоящими (больше, чем у людей над ней).

   «Ноль найденного — провал»: личина ищется в списке по имени, не
   нашлась — место -1, проверка красная.

   Данные рейтинга — во временной папке (боевые не трогаем).

   Запуск:                node tests/рейтинг-личин.js
   Ломающий запуск:       node tests/рейтинг-личин.js --сломать
   (портит функцию опуститьЛичин В ПАМЯТИ, файл проекта не меняется;
   проверка обязана покраснеть).

   Выход 0 — провалов нет, 1 — есть, 2 — порча не применилась.
   ===================================================================== */

const path = require('path');
const os = require('os');
const fs = require('fs');
const Module = require('module');

const КОРЕНЬ = path.join(__dirname, '..');
const СЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;

/* Данные уводим ДО подключения рейтинга: иначе первое же чтение возьмёт боевые. */
const СВОЯ_ПАПКА = path.join(os.tmpdir(), 'рейтинг-личин-' + process.pid);
fs.mkdirSync(СВОЯ_ПАПКА, { recursive: true });
process.env.GAMES_DATA = СВОЯ_ПАПКА;
process.env.ДАННЫЕ_ИГРЫ = СВОЯ_ПАПКА;

/* Часы двигаем вперёд: так «сегодня» меняется и снимок мест снимается заново. */
const настоящееВремя = Date.now.bind(Date);
let сдвигВремени = 0;
Date.now = function () { return настоящееВремя() + сдвигВремени; };

/* Ломающий запуск: рейтинг грузим из памяти с испорченной функцией, под
   настоящим именем в кэше require. Файл проекта не меняется. */
if (СЛОМАТЬ) {
  const путь = path.join(КОРЕНЬ, 'server', 'рейтинг.js');
  let текст = fs.readFileSync(путь, 'utf8');
  const было = 'function опуститьЛичин(список, сМеста = 4) {';
  if (текст.split(было).length !== 2) { console.log('порча не применилась'); process.exit(2); }
  текст = текст.replace(было, было + ' return список;');
  const м = new Module(путь, module);
  м.filename = путь;
  м.paths = Module._nodeModulePaths(path.dirname(путь));
  м._compile(текст, путь);
  require.cache[путь] = м;
  м.loaded = true;
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: потолок личин выключен в памяти — проверка обязана покраснеть ***');
}

const рейтинг = require(path.join(КОРЕНЬ, 'server', 'рейтинг.js'));
const личины = require(path.join(КОРЕНЬ, 'server', 'личины.js'));

let проверок = 0;
const провалы = [];
function проверить(условие, что) {
  проверок++;
  if (!условие) { провалы.push(что); console.log('  ✗ ' + что); }
  else console.log('  ✓ ' + что);
}

const НОМЕР_ЛИЧИНЫ = 900000000000001;
const ИМЯ_ЛИЧИНЫ = 'ЛичинаТест';
const ЛЮДИ = [100001, 100002, 100003];
const ИГРЫ = ['шашки', 'дурак'];

function ученик(номер, имя, победил) {
  return { номер: номер, имя: имя, этоБот: false, победил: победил, ничья: false };
}

/* Чистый рейтинг: N людей, личина выигрывает у каждого по партии в каждой игре. */
function засеять(людей) {
  рейтинг.забытьВсё();
  рейтинг.включитьЗапись();
  for (const игра of ИГРЫ) {
    for (let i = 0; i < людей; i++) {
      рейтинг.учестьПартию(игра, [
        ученик(НОМЕР_ЛИЧИНЫ, ИМЯ_ЛИЧИНЫ, true),
        ученик(ЛЮДИ[i], 'Человек' + (i + 1), false)
      ]);
    }
  }
}

function местоЛичины(строки) {
  const индекс = строки.findIndex(function (с) { return с.имя === ИМЯ_ЛИЧИНЫ; });
  return индекс === -1 ? -1 : индекс + 1;
}

function очкиЛичины(строки) {
  const с = строки.find(function (с) { return с.имя === ИМЯ_ЛИЧИНЫ; });
  return с ? с.очки : -1;
}

function наибольшиеОчкиЛюдей(строки) {
  return Math.max.apply(null, строки.filter(function (с) { return с.имя !== ИМЯ_ЛИЧИНЫ; })
    .map(function (с) { return с.очки; }));
}

function сценарийЛичинаЛидер(людей) {
  const ожидаемое = Math.min(4, людей + 1);
  console.log('\n== ' + людей + ' чел. + личина с наибольшими очками: ждём место ' + ожидаемое + ' ==');
  засеять(людей);
  сдвигВремени += 2 * 24 * 3600 * 1000;

  const я = ЛЮДИ[0];
  const друзья = ЛЮДИ.slice(1, людей).concat([НОМЕР_ЛИЧИНЫ]);

  const списки = [
    ['срез игры', рейтинг.срезДляИгрока('шашки', я).верхушка],
    ['«Все игры»', рейтинг.срезПоВсемИграм(я).верхушка],
    ['«Друзья», одна игра', рейтинг.срезПоСписку('шашки', я, друзья).верхушка],
    ['«Друзья», все игры', рейтинг.срезПоВсемИграмПоСписку(я, друзья).верхушка]
  ];
  for (const [название, строки] of списки) {
    проверить(местоЛичины(строки) === ожидаемое,
      название + ': личина на месте ' + ожидаемое + ' (по факту ' + местоЛичины(строки) + ')');
    проверить(очкиЛичины(строки) > наибольшиеОчкиЛюдей(строки),
      название + ': очки личины настоящие и больше, чем у людей (' + очкиЛичины(строки) + ')');
    проверить(строки.slice(0, ожидаемое - 1).every(function (с) { return с.имя !== ИМЯ_ЛИЧИНЫ; }),
      название + ': выше личины — только люди');
  }

  /* «Моё место» у самой личины тоже считается по опущенному списку. */
  const личинаКакЯ = рейтинг.срезДляИгрока('шашки', НОМЕР_ЛИЧИНЫ);
  проверить(личинаКакЯ.я && личинаКакЯ.я.место === ожидаемое,
    '«моё место» личины в срезе игры = ' + ожидаемое);

  /* Снимок вчерашних мест — файл на диске, снятый после «смены суток». */
  проверить(fs.existsSync(рейтинг.ФАЙЛ_МЕСТ), 'файл снимка мест записан');
  const снимок = JSON.parse(fs.readFileSync(рейтинг.ФАЙЛ_МЕСТ, 'utf8'));
  const местаШашки = снимок.сегодня && снимок.сегодня.места && снимок.сегодня.места['шашки'];
  const местаВсе = снимок.сегодня && снимок.сегодня.места && снимок.сегодня.места['_всеИгры'];
  проверить(Boolean(местаШашки) && местаШашки[String(НОМЕР_ЛИЧИНЫ)] === ожидаемое,
    'снимок мест, шашки: личина на месте ' + ожидаемое + ' (по факту ' + (местаШашки && местаШашки[String(НОМЕР_ЛИЧИНЫ)]) + ')');
  проверить(Boolean(местаВсе) && местаВсе[String(НОМЕР_ЛИЧИНЫ)] === ожидаемое,
    'снимок мест, все игры: личина на месте ' + ожидаемое + ' (по факту ' + (местаВсе && местаВсе[String(НОМЕР_ЛИЧИНЫ)]) + ')');
}

function сценарийБезЛичин() {
  console.log('\n== без личин порядок не меняется ==');
  рейтинг.забытьВсё();
  рейтинг.включитьЗапись();
  /* Человек i выигрывает i партий у «врага» — очки по убыванию номера не совпадают с номером. */
  const очерёдность = [[100004, 3], [100005, 1], [100006, 2], [100007, 4]];
  for (const [номер, побед] of очерёдность) {
    for (let k = 0; k < побед; k++) {
      рейтинг.учестьПартию('шашки', [
        ученик(номер, 'Ч' + номер, true),
        ученик(300000 + номер * 10 + k, 'Враг', false)
      ]);
    }
  }
  const строки = рейтинг.срезДляИгрока('шашки', 100004).верхушка;
  const людиВерхушки = строки.filter(function (с) { return с.имя.indexOf('Ч1000') === 0; });
  проверить(людиВерхушки.length === 4, 'нашлись все 4 человека в списке (' + людиВерхушки.length + ')');
  const очки = людиВерхушки.map(function (с) { return с.очки; });
  проверить(очки.every(function (о, i) { return i === 0 || очки[i - 1] >= о; }),
    'без личин список по убыванию очков: ' + очки.join(', '));
  const образец = [{ номер: 1 }, { номер: 2 }, { номер: 3 }, { номер: 4 }];
  проверить(рейтинг.опуститьЛичин(образец) === образец, 'без личин функция отдаёт тот же массив');
}

function ч(номер) { return { номер: номер }; }
function л(порядок) { return { номер: 900000000000000 + порядок }; }
function номера(список) { return список.map(function (з) { return з.номер; }); }
function одинаково(а, б) { return JSON.stringify(а) === JSON.stringify(б); }

function сценарийФункция() {
  console.log('\n== сама функция опуститьЛичин ==');
  const у = рейтинг.опуститьЛичин;
  проверить(личины.этоЛичина(л(1).номер) && !личины.этоЛичина(1), 'образцы личины и человека распознаются');

  проверить(одинаково(номера(у([л(1), ч(1), ч(2), ч(3), ч(4)])), номера([ч(1), ч(2), ч(3), л(1), ч(4)])),
    'личина 1-я, людей хватает → 4-я');
  проверить(одинаково(номера(у([ч(1), ч(2), л(1), ч(3)])), номера([ч(1), ч(2), ч(3), л(1)])),
    'личина 3-я → 4-я');
  проверить(одинаково(номера(у([ч(1), ч(2), ч(3), л(1), ч(4)])), номера([ч(1), ч(2), ч(3), л(1), ч(4)])),
    'личина уже 4-я → не трогаем');
  проверить(одинаково(номера(у([л(1), л(2), ч(1), ч(2), ч(3)])), номера([ч(1), ч(2), ч(3), л(1), л(2)])),
    'две личины сверху → 4-я и 5-я в прежнем порядке');
  проверить(одинаково(номера(у([л(1), ч(1)])), номера([ч(1), л(1)])),
    'один человек → личина сразу после него (2-я)');
  проверить(одинаково(номера(у([л(1), ч(1), ч(2)])), номера([ч(1), ч(2), л(1)])),
    'два человека → личина 3-я');
  проверить(одинаково(номера(у([л(1), л(2)])), номера([л(1), л(2)])),
    'людей нет → порядок как был');
  проверить(одинаково(номера(у([])), []), 'пустой список не падает');

  const исходный = [л(1), ч(1), ч(2), ч(3)];
  const копия = исходный.slice();
  у(исходный);
  проверить(одинаково(исходный, копия), 'исходный массив не портится');
}

console.log('Потолок личин в рейтинге' + (СЛОМАТЬ ? ' (ЛОМАЮЩИЙ ЗАПУСК)' : ''));
проверить(личины.этоЛичина(НОМЕР_ЛИЧИНЫ), 'номер тестовой личины действительно личина');
сценарийЛичинаЛидер(3);
сценарийЛичинаЛидер(1);
сценарийБезЛичин();
сценарийФункция();

try { fs.rmSync(СВОЯ_ПАПКА, { recursive: true, force: true }); } catch (сбой) { /* не страшно */ }

console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалы.length);
if (провалы.length > 0) {
  console.log('Провалы:');
  провалы.forEach(function (п) { console.log(' - ' + п); });
  process.exit(1);
}
