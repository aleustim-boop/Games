/* =====================================================================
   РЕЙТИНГ: потолок личин («не выше 4-го места»), этап Э8 «Живых лобби».

   Личина — не человек. Решение В2 (штаб/план-живые-лобби.md): рейтинг
   выглядит живым, но тройка лучших — всегда люди. Личина, которой счёт
   даёт место выше 4-го, показывается ниже людей, не ниже 4-го места;
   людей меньше трёх — сразу после последнего человека (выше человека
   она не бывает). Очки не меняются — только порядок показа.

   Что проверяем (всё в node, без браузера и без сервера):
     1. Три человека + личина с наибольшими очками: личина 4-я в КАЖДОМ
        списке — срез игры, «Все игры», «Друзья» по игре, «Друзья» по
        всем играм и снимок вчерашних мест (файл на диске).
     2. Один человек + личина выше него: личина 2-я везде.
     3. Без личин порядок не меняется (тот же массив, по убыванию очков).
     4. Сама функция опуститьЛичин на разборе случаев (две личины, нет
        людей, личина уже на 4-м, исходный массив не портится).
     Очки личины в строке остаются настоящими (больше, чем у людей над ней).

   «Ноль найденного — провал»: личина ищется в списке по имени, не
   нашлась — место -1, проверка красная.

   Данные рейтинга — во временной папке (боевые не трогаем).

   Запуск:                node tests/рейтинг-личин.js
   Ломающий запуск:       node tests/рейтинг-личин.js --сломать
   (портит функцию опуститьЛичин В ПАМЯТИ, файл проекта не меняется;
   проверка обязана покраснеть).
   Ломающий запуск силы:  node tests/рейтинг-личин.js --сломать-силу
   (в server/сила-игроков.js убирает опускание личин, в памяти).

   Дополнительно (замечание ревьюера Э8):
     5. Таблица «Сила игры» (server/сила-игроков.js): личина с наибольшей
        силой — не 1-я, люди выше; личина с силой, равной человеку, тоже.
        Записи силы кладём прямо в файл памяти силы (во временной папке) —
        так сила задаётся точно, без сотен партий.
     6. Срезы «по правилу» и «по составу» (срезСоВсемиПравилами).
     7. Равные очки у личины и человека: личина всё равно ниже.

   Выход 0 — провалов нет, 1 — есть, 2 — порча не применилась.
   ===================================================================== */

