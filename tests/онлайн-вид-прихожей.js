/* =====================================================================
   ВИД ПРИХОЖЕЙ ДЛЯ ТРЁХ ИГР НА ДВОИХ (штаб/план-онлайн-как-дурак.md, Э2)

   Что проверяем. server/игры/нарды.js и server/игры/шашки.js уже умели
   отдавать поля прихожей (застолом, яХозяин, можноНачать) для стола-
   компании (Э1 в server/комнаты.js). Этот прогон добавляет к ним
   server/игры/морской-бой.js и проверяет всех троих одним сценарием —
   так же, как играл бы хозяин на телефоне:

     создать стол компанией → у хозяина в виде есть места, яХозяин=да,
     можноНачать=нет (один за столом) → второй входит по коду →
     можноНачать=да, у гостя яХозяин=нет → «Начать» от гостя — отказ →
     «Начать» от хозяина — партия идёт у обоих.

   Буквы — по игре: А — нарды, Б — шашки, В — морской бой. Плюс общая
   буква Г — сторож лишних полей: в «застолом» нет внутренних ключей
   сервера и других незнакомых имён, а сам вид не тащит ничего похожего
   на пропуск, токен или номер в Telegram.

   Какой server/ проверять — довод «--корень <папка>», как у
   tests/онлайн-компания-на-двоих.js. Свой сервер — на порту 8828
   (боевой 8790 не трогаем), Telegram поддельный, данные игры — во
   временной папке.

   Запуск:
       node tests/онлайн-вид-прихожей.js
       node tests/онлайн-вид-прихожей.js --корень <папка-с-копией>

   Ломающий прогон:
       node tests/онлайн-вид-прихожей.js --сломать
   Копия server/ и js/ во временной папке, в ней у морского боя убрано
   присваивание «застолом» в видДляИгрока — прогон на копии обязан
   покраснеть буквой В. Место порчи не нашлось — тоже провал.

   Выход 0 — провалов нет, 1 — есть.
   ===================================================================== */

const path = require('path');
const os = require('os');
const fs = require('fs');
const http = require('http');
const { spawnSync } = require('child_process');

const ПРОЕКТ = path.join(__dirname, '..');
const ПОРТ = 8828;
const ХОЗЯИН_АДРЕС = '127.0.0.1';

const ТОКЕН_ДЛЯ_ПРОБЫ = '1234567:VYDUMANNYY-TOKEN-DLYA-PROVERKI-vida-prihozhey';

/* Три игры на двоих без своей прихожей до Э1 — их и проверяем здесь. */
const ИГРЫ = ['нарды', 'шашки', 'морской-бой'];
const БУКВА_ИГРЫ = { 'нарды': 'А', 'шашки': 'Б', 'морской-бой': 'В' };

/* Что разрешено лежать в одном месте списка «застолом» — общее для всех
   трёх игр плюс «цвет», который добавляют нарды и шашки. Внутреннего
   ключа места сервера («человек», «первый») или пропуска тут быть
   не должно ни у одной игры. */
const ПОЛЯ_МЕСТА = new Set([
  'номер', 'имя', 'этоЯ', 'этоБот', 'хозяин', 'наСвязи', 'ушёл', 'хочетЕщё', 'цвет'
]);

/* Приметы полей, которым нет места в ответе игроку нигде в дереве вида:
   тот же смысл, что у ОПАСНЫЕ_ПРИМЕТЫ в tests/сторож-полей.js, но здесь
   своя маленькая копия — заводить зависимость от чужого файла ради трёх
   проверок незачем. */
const ОПАСНЫЕ_ПРИМЕТЫ = [
  { примета: /пропуск|токен|секрет|пароль/i, чем: 'похоже на пропуск игрока' },
  { примета: /^ключ$/i, чем: 'похоже на внутренний ключ места сервера' },
  { примета: /telegram|tg[_-]|chat|user[_-]?id/i, чем: 'похоже на номер игрока в Telegram' }
];

function доводПосле(имя) {
  const где = process.argv.indexOf(имя);
  return где !== -1 ? process.argv[где + 1] : null;
}

/* =====================================================================
   РЕЖИМ «--сломать»: копия с порчей и прогон проверки на ней
   ===================================================================== */

const ПОРЧА_МОРСКОГО_БОЯ = {
  найти:
    "    v.застолом = d.места.map(м => ({\n" +
    "      номер: номерМеста(м.ключ), имя: м.имя, этоЯ: м.ключ === кто,\n" +
    "      этоБот: !!м.этоБот, хозяин: !!м.хозяин, наСвязи: м.наСвязи !== false,\n" +
    "      ушёл: !!м.ушёл, хочетЕщё: !!м.хочетЕщё\n" +
    "    }));\n",
  заменить: '',
  краснеютБуквы: ['В']
};

function сделатьКопию(папка) {
  for (const часть of ['server', 'js']) {
    fs.cpSync(path.join(ПРОЕКТ, часть), path.join(папка, часть), {
      recursive: true,
      filter: function (откуда) {
        const имя = path.basename(откуда);
        return имя !== 'данные' && имя !== 'node_modules';
      }
    });
  }
}

function заменитьРовноОдинРаз(текст, найти, заменить) {
  const где = текст.indexOf(найти);
  if (где === -1) return null;
  if (текст.indexOf(найти, где + 1) !== -1) return null;   // двусмысленно — тоже не нашли
  return текст.slice(0, где) + заменить + текст.slice(где + найти.length);
}

function ломать() {
  console.log('=== Ломающий прогон «вид прихожей»: морской бой без застолом обязан покраснеть ===');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'вид-прихожей-лом-'));
  console.log('копия в ' + папка + '\n');
  сделатьКопию(папка);

  const файл = path.join(папка, 'server', 'игры', 'морской-бой.js');
  const текст = заменитьРовноОдинРаз(fs.readFileSync(файл, 'utf8').replace(/\r\n/g, '\n'),
    ПОРЧА_МОРСКОГО_БОЯ.найти, ПОРЧА_МОРСКОГО_БОЯ.заменить);
  if (текст === null) {
    console.log('ПРОВАЛ: место порчи в server/игры/морской-бой.js не найдено (или найдено дважды)');
    try { fs.rmSync(папка, { recursive: true, force: true }); } catch (сбой) { /* не страшно */ }
    process.exit(1);
    return;
  }
  fs.writeFileSync(файл, текст, 'utf8');

  const прогон = spawnSync(process.execPath, [__filename, '--корень', папка], {
    encoding: 'utf8', timeout: 180000
  });
  const вывод = (прогон.stdout || '') + (прогон.stderr || '');
  const красные = new Set();
  (вывод.match(/ПРОВАЛ \[[А-Я]\]/g) || []).forEach(function (с) { красные.add(с.slice(8, 9)); });
  const недостаёт = ПОРЧА_МОРСКОГО_БОЯ.краснеютБуквы.filter(function (б) { return !красные.has(б); });
  const ок = прогон.status === 1 && недостаёт.length === 0;

  console.log((ок ? 'красная, как надо' : 'ПРОВАЛ (осталась зелёной)') +
    ': морской бой без застолом; код выхода ' + прогон.status +
    ', покраснели буквы: ' + (Array.from(красные).join(', ') || 'ни одна'));
  if (!ок) console.log(вывод);

  try { fs.rmSync(папка, { recursive: true, force: true }); } catch (сбой) { /* не страшно */ }
  process.exit(ок ? 0 : 1);
}

/* =====================================================================
   ОБЫЧНЫЙ РЕЖИМ: сама проверка
   ===================================================================== */

let проверок = 0;
const провалы = [];

function проверить(буква, условие, что) {
  проверок++;
  if (!условие) {
    провалы.push('[' + буква + '] ' + что);
    console.log('  ПРОВАЛ [' + буква + '] ' + что);
  } else {
    console.log('  ок [' + буква + '] ' + что);
  }
}

function спросить(путь, тело) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН_АДРЕС, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (сбой) { разобрано = null; }
        готово({ код: ответ.statusCode, тело: разобрано || {} });
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

/** Незнакомые опасные поля где угодно в дереве вида — сторож без белого
    списка по игре, годится сразу для всех трёх (см. шапку файла). */
function найтиОпасныеПоля(узел, путь, буква, откуда) {
  if (!узел || typeof узел !== 'object') return;
  Object.keys(узел).forEach(function (поле) {
    const опасное = ОПАСНЫЕ_ПРИМЕТЫ.find(function (п) { return п.примета.test(поле); });
    if (опасное) {
      проверить(буква, false, откуда + ': в виде поле «' + путь + поле + '» — ' + опасное.чем +
        ' (значение: ' + JSON.stringify(узел[поле]) + ')');
    }
    найтиОпасныеПоля(узел[поле], путь + поле + '.', буква, откуда);
  });
}

/** Строка «застолом» — только разрешённые поля, внутреннего ключа места нет. */
function проверитьМеста(буква, застолом, откуда) {
  проверить(буква, Array.isArray(застолом) && застолом.length > 0,
    откуда + ': «застолом» — непустой список');
  if (!Array.isArray(застолом)) return;
  застолом.forEach(function (место, номер) {
    Object.keys(место).forEach(function (поле) {
      проверить(буква, ПОЛЯ_МЕСТА.has(поле),
        откуда + ': в месте №' + (номер + 1) + ' лишнее поле «' + поле + '» = ' +
        JSON.stringify(место[поле]));
    });
  });
}

async function проверитьВсё() {
  async function создать(игра) {
    const ответ = await спросить('/создать', { имя: 'Хозяин', игра: игра, компанией: true });
    return ответ.тело || {};
  }
  async function войти(код, имя) {
    const ответ = await спросить('/войти', { код: код, имя: имя });
    return ответ.тело || {};
  }
  async function вид(код, пропуск) {
    const ответ = await спросить('/состояние', { код: код, пропуск: пропуск });
    return ответ.тело && ответ.тело.состояние ? ответ.тело.состояние : {};
  }
  async function действие(код, пропуск, слово) {
    const ответ = await спросить('/ход', { код: код, пропуск: пропуск, действие: слово });
    return ответ.тело || {};
  }

  for (const игра of ИГРЫ) {
    const буква = БУКВА_ИГРЫ[игра];
    console.log('\n' + буква + '. ' + игра + ' — вид прихожей как у дурака');

    const стол = await создать(игра);
    проверить(буква, Boolean(стол.код && стол.пропуск), 'стол создан компанией');

    const видОдного = await вид(стол.код, стол.пропуск);
    проверить(буква, видОдного.этап === 'ожидание',
      'один за столом — этап «ожидание» (этап: ' + видОдного.этап + ')');
    проверить(буква, Array.isArray(видОдного.застолом) && видОдного.застолом.length === 1 &&
      видОдного.застолом[0].этоЯ === true, 'за столом один — «Вы»');
    проверить(буква, видОдного.яХозяин === true, 'у хозяина яХозяин: true');
    проверить(буква, видОдного.можноНачать === false, 'одному начинать нельзя');

    const гость = await войти(стол.код, 'Гость');
    проверить(буква, Boolean(гость.пропуск),
      'второй вошёл по коду' + (гость.причина ? ' (' + гость.причина + ')' : ''));

    const видХозяинаВдвоём = await вид(стол.код, стол.пропуск);
    проверить(буква, видХозяинаВдвоём.можноНачать === true,
      'после входа второго у хозяина «можно начать» = да');
    проверить(буква, Array.isArray(видХозяинаВдвоём.застолом) && видХозяинаВдвоём.застолом.length === 2,
      'у хозяина за столом двое');

    const видГостя = await вид(стол.код, гость.пропуск);
    проверить(буква, видГостя.яХозяин === false, 'у гостя яХозяин: false');

    const стартГостя = await действие(стол.код, гость.пропуск, 'начать');
    проверить(буква, стартГостя.принято === false && typeof стартГостя.причина === 'string',
      '«Начать» от гостя — отказ словами (' + стартГостя.причина + ')');

    const стартХозяина = await действие(стол.код, стол.пропуск, 'начать');
    проверить(буква, стартХозяина.принято === true, '«Начать» от хозяина принят');

    const видПослеСтарта = await вид(стол.код, стол.пропуск);
    const видГостяПослеСтарта = await вид(стол.код, гость.пропуск);
    проверить(буква, видПослеСтарта.этап === 'игра', 'у хозяина партия идёт (этап: ' + видПослеСтарта.этап + ')');
    проверить(буква, видГостяПослеСтарта.этап === 'игра', 'у гостя партия тоже идёт (этап: ' + видГостяПослеСтарта.этап + ')');

    console.log('  Г. сторож лишних полей — ' + игра);
    проверитьМеста('Г', видХозяинаВдвоём.застолом, игра + ' (хозяин, прихожая)');
    проверитьМеста('Г', видГостя.застолом, игра + ' (гость, прихожая)');
    найтиОпасныеПоля(видПослеСтарта, '', 'Г', игра + ' (хозяин, партия идёт)');
    найтиОпасныеПоля(видГостяПослеСтарта, '', 'Г', игра + ' (гость, партия идёт)');
  }
}

async function проверять() {
  const корень = path.resolve(доводПосле('--корень') || ПРОЕКТ);

  const папкаДанных = fs.mkdtempSync(path.join(os.tmpdir(), 'вид-прихожей-данные-'));
  process.env.ДАННЫЕ_ИГРЫ = папкаДанных;

  const сервера = require(path.join(корень, 'server', 'сервер.js'));

  console.log('=== Вид прихожей: нарды, шашки, морской бой (Э2) ===');
  console.log('server/ из ' + корень);
  console.log('свой сервер на http://' + ХОЗЯИН_АДРЕС + ':' + ПОРТ + ' (боевой 8790 не трогаем)');

  сервера.оснасткаДляПроверки(ТОКЕН_ДЛЯ_ПРОБЫ, function () { return { ok: true }; });
  const сервер = сервера.создатьСервер();
  await new Promise(function (готово, беда) {
    сервер.once('error', беда);
    сервер.listen(ПОРТ, ХОЗЯИН_АДРЕС, готово);
  });

  let сбой = null;
  try {
    await проверитьВсё();
  } catch (беда) {
    сбой = беда;
  }

  сервер.close();
  сервера.оснасткаДляПроверки();

  console.log('\n----------------------------------------');
  if (сбой) {
    console.log('ПРОВЕРКА ОБОРВАЛАСЬ: ' + сбой.message);
    console.log(сбой.stack);
  }
  if (проверок === 0) провалы.push('ни одной проверки не выполнено');
  for (const беда of провалы) console.log('  - ' + беда);
  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалы.length);
  try { fs.rmSync(папкаДанных, { recursive: true, force: true }); } catch (сбойУборки) { /* не страшно */ }
  process.exit(сбой || провалы.length > 0 ? 1 : 0);
}

if (process.argv.indexOf('--сломать') !== -1) ломать();
else проверять();
