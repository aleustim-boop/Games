async function главное() {
  console.log('=== Шашки по сети: целая партия ===');
  console.log('сервер: http://' + ХОСТ + ':' + ПОРТ);
  let было;
  try {
    было = await здоровье();
  } catch (сбой) {
    console.error('Сервер комнат не отвечает. Поднимите его: node server/сервер.js ' + ПОРТ + ' --без-памяти');
    process.exit(1);
  }
  console.log('сервер жив, комнат до прогона: ' + было.комнат);

  /* ---- 1. Комната на двоих ---- */
  const создание = await запрос('/создать', { игра: 'шашки' });
  проверить(создание.номер === 200 && создание.данные.код, 'шашечную комнату завести не вышло');
  if (!создание.данные.код) { доложить(); return; }
  сторож.осмотретьКонверт(создание.данные, 'создание');
  const первый = new Игрок('хозяин', создание.данные.код, создание.данные.пропуск, создание.данные.состояние);

  const вход = await запрос('/войти', { код: создание.данные.код });
  проверить(вход.номер === 200 && вход.данные.пропуск, 'второй не смог войти по коду');
  сторож.осмотретьКонверт(вход.данные, 'вход');
  const второй = new Игрок('гость', вход.данные.код, вход.данные.пропуск, вход.данные.состояние);

  await первый.обновить();
  проверить(первый.вид.игра === 'шашки', 'комната помечена игрой «шашки» (пришло «' + первый.вид.игра + '»)');
  проверить(Array.isArray(первый.вид.доска) && первый.вид.доска.length === 8, 'доска пришла восемью строками');
  проверить(первый.вид.мойЦвет && второй.вид.мойЦвет && первый.вид.мойЦвет !== второй.вид.мойЦвет,
    'цвета розданы разные: у хозяина «' + первый.вид.мойЦвет + '», у гостя «' + второй.вид.мойЦвет + '»');

  /* ---- 2. Отказы (пока партия идёт) ---- */
  await проверитьОтказы(первый, второй);

  /* ---- 2б. Длинный опрос: им страница ждёт чужого хода ---- */
  console.log('\n=== Длинный опрос: узнаём о чужом ходе ===');
  {
    await первый.обновить();
    await второй.обновить();
    const ходящий = первый.вид.яХожу ? первый : второй;
    const ждущий = первый.вид.яХожу ? второй : первый;

    /* Ждущий спрашивает «что нового» с той версией, которую видит сейчас, —
       и остаётся висеть, пока соперник не сходит. Ровно так ждёт телефон. */
    const ожидание = ждущий.чтоНового(ждущий.вид.версия, 20000);

    const { ходы } = ходыИзКартинки(ходящий.вид.доска, ходящий.вид.чейХод);
    const выбран = выбратьХод(ходы);
    const сделали = await ходящий.ход({
      действие: 'ход', откуда: выбран.откуда, куда: выбран.куда,
      побитые: выбран.побитые, станетДамкой: выбран.станетДамкой
    });
    проверить(сделали.принято === true, 'ход для проверки длинного опроса не приняли');

    const новость = await ожидание;
    console.log('  ждущий дождался: изменилось=' + (новость.данные && новость.данные.изменилось) +
      ', ход ' + выбран.откуда + '→' + выбран.куда);
    проверить(новость.номер === 200, 'длинный опрос ответил не 200 (' + новость.номер + ')');
    проверить(новость.данные && новость.данные.изменилось === true,
      'длинный опрос не принёс новость о чужом ходе');
    сторож.осмотретьКонверт(новость.данные, 'длинный опрос');
    const видПоОпросу = новость.данные && новость.данные.состояние;
    проверить(!!видПоОпросу, 'в новости нет состояния стола');
    if (видПоОпросу) {
      сторож.осмотреть(видПоОпросу, 'длинный опрос');
      проверить(видПоОпросу.версия > ждущий.вид.версия,
        'версия стола после чужого хода не выросла');
      проверить(!!видПоОпросу.последнийХод && видПоОпросу.последнийХод.мой === false,
        'в новости не рассказано, каким был ЧУЖОЙ ход');
      if (видПоОпросу.последнийХод) {
        проверить(видПоОпросу.последнийХод.откуда === выбран.откуда &&
                  видПоОпросу.последнийХод.куда === выбран.куда,
          'длинный опрос назвал не тот ход, который сделал соперник');
        проверить(Array.isArray(видПоОпросу.последнийХод.путь) && видПоОпросу.последнийХод.путь.length >= 2,
          'у чужого хода в новости нет пути — на экране он будет телепортацией');
      }
      ждущий.вид = видПоОпросу;
    }
  }

  /* ---- 2в. Знаки внимания: их только что включили и у шашек ---- */
  console.log('\n=== Знаки внимания за шашечным столом ===');
  {
    await первый.обновить();
    проверить(первый.вид.знакиВниманияЕсть === true, 'сервер говорит, что знаки внимания есть');
    проверить(первый.вид.броскиЕсть === true, 'сервер говорит, что броски есть');

    const послал = await первый.ход({ действие: 'эмоция', номер: 1 });
    проверить(послал.принято === true, 'знак внимания не приняли: ' + послал.причина);

    await второй.обновить();
    const чужой = второй.вид.знакВнимания;
    console.log('  соперник увидел: ' + JSON.stringify(чужой));
    проверить(!!чужой, 'соперник не увидел знак вовсе');
    if (чужой) {
      проверить(чужой.этоЯ === false, 'чужой знак помечен как свой (этоЯ = ' + чужой.этоЯ + ')');
      проверить(typeof чужой.номер === 'number', 'номер знака пришёл не числом');
      /* Внутренних имён мест наружу уходить не должно: имя в знаке — то,
         которым человек подписался, а не служебное «первый»/«второй». */
      проверить(!/^(первый|второй|третий|четвёртый)$/i.test(String(чужой.имя || '')),
        'в знаке видно внутреннее имя места: «' + чужой.имя + '»');
      проверить(!/место|ключ|пропуск/i.test(JSON.stringify(чужой)),
        'в знаке есть служебные поля: ' + JSON.stringify(чужой));
    }
    const свой = (await первый.обновить()).знакВнимания;
    проверить(!свой || свой.этоЯ === true, 'свой же знак пришёл как чужой');

    /* Долбёжка: двенадцать нажатий подряд. Сервер обязан пропустить одно
       и отказать остальным СЛОВАМИ, а стол после этого — остаться живым. */
    let принято = 0;
    let отказовСоСловами = 0;
    for (let i = 0; i < 12; i++) {
      const о = await первый.ход({ действие: 'эмоция', номер: 2 });
      if (о.принято) принято++;
      else if (typeof о.причина === 'string' && о.причина.length > 5) отказовСоСловами++;
    }
    console.log('  двенадцать нажатий подряд: принято ' + принято + ', отказов словами ' + отказовСоСловами);
    проверить(принято <= 1, 'долбёжку знаками сервер не придержал (принято ' + принято + ')');
    проверить(принято + отказовСоСловами === 12, 'на часть нажатий сервер ответил молча');

    /* Главное: после долбёжки стол не оглох — ход по-прежнему проходит. */
    await первый.обновить();
    await второй.обновить();
    const ходящий = первый.вид.яХожу ? первый : второй;
    const { ходы } = ходыИзКартинки(ходящий.вид.доска, ходящий.вид.чейХод);
    const проба = ходы[0];
    const после = await ходящий.ход({
      действие: 'ход', откуда: проба.откуда, куда: проба.куда,
      побитые: проба.побитые, станетДамкой: проба.станетДамкой
    });
    проверить(после.принято === true, 'после долбёжки знаками стол оглох: ход не приняли');
  }

  /* ---- 3. Партия до конца ---- */
  console.log('\n=== Партия двух живых игроков ===');
  const начало = Date.now();
  const итоги = await сыгратьПартию(первый, второй, 'партия');
  const секунд = ((Date.now() - начало) / 1000).toFixed(1);

  await первый.обновить();
  await второй.обновить();
  console.log('  ходов ' + итоги.ходов + ', боёв ' + итоги.боёв + ', цепочек боёв ' + итоги.цепочек +
    ' (длиннейшая — ' + итоги.длиннейшаяЦепочка + ' взятия), дамок появилось ' + итоги.дамокПоявилось +
    ', заняло ' + секунд + ' с');

  проверить(первый.вид.завершена === true, 'партия дошла до конца');
  const итогХозяина = первый.вид.итог || {};
  const итогГостя = второй.вид.итог || {};
  console.log('  итог: победитель «' + итогХозяина.победитель + '», ничья ' + Boolean(итогХозяина.ничья) +
    ', причина «' + итогХозяина.причина + '»');
  проверить(!!первый.вид.итог && !!второй.вид.итог, 'итог показан обоим');
  проверить(Boolean(итогХозяина.ничья) === Boolean(итогГостя.ничья), 'про ничью игроки думают по-разному');
  if (!итогХозяина.ничья) {
    проверить(Boolean(итогХозяина.яВыиграл) !== Boolean(итогГостя.яВыиграл),
      'выигравшим считают себя оба или никто');
    проверить(итогХозяина.победитель === итогГостя.победитель, 'победитель назван по-разному');
  }
  проверить(итоги.боёв > 0, 'за партию был хотя бы один бой (боёв ' + итоги.боёв + ')');

  /* ---- 4. Реванш ---- */
  console.log('\n=== Реванш ===');
  const ещё1 = await первый.ход({ действие: 'ещё' });
  проверить(ещё1.принято === true, 'хозяин не смог попросить реванш: ' + ещё1.причина);
  const ещё2 = await второй.ход({ действие: 'ещё' });
  проверить(ещё2.принято === true, 'гость не смог согласиться на реванш: ' + ещё2.причина);
  await первый.обновить();
  await второй.обновить();

  const начальная = Правила.картинкаПартии(Правила.создатьПартию());
  console.log('  доска после реванша: ' + (первый.вид.доска || []).join(' | '));
  проверить(первый.вид.завершена === false, 'после реванша партия снова идёт');
  проверить(JSON.stringify(первый.вид.доска) === JSON.stringify(начальная),
    'доска встала в начальное положение');
  проверить(!первый.вид.последнийХод && !второй.вид.последнийХод,
    'прошлый ход не перекочевал в новую партию');
  проверить(!первый.вид.итог && !второй.вид.итог, 'прошлый итог убран с экрана');

  await первый.выйти();
  await второй.выйти();

  /* ---- 5. Бот по сети ---- */
  console.log('\n=== Партия против бота по сети ===');
  const сБотом = await запрос('/создать', { игра: 'шашки' });
  проверить(сБотом.номер === 200 && сБотом.данные.код, 'комнату для игры с ботом завести не вышло');
  const человек = new Игрок('человек', сБотом.данные.код, сБотом.данные.пропуск, сБотом.данные.состояние);
  const посадка = await человек.ход({ действие: 'бот' });
  console.log('  посадка бота: ' + (посадка.принято ? 'принято' : 'отказ — «' + посадка.причина + '»'));

  if (!посадка.принято) {
    console.log('  (бота за шашечный стол сервер пока не сажает — проверить партию с ботом не удалось)');
  } else {
    /* Бот сел, но партия ждёт хозяина: после посадки комната остаётся
       в «ожидании», пока хозяин не нажмёт «Начать». Ровно это и делаем. */
    const начали = await человек.ход({ действие: 'начать' });
    проверить(начали.принято === true, 'хозяин не смог начать партию с ботом: ' + начали.причина);
    let ходов = 0;
    let встал = false;
    for (let шаг = 0; шаг < ПОТОЛОК_ХОДОВ; шаг++) {
      await человек.обновить();
      if (человек.вид.завершена) break;
      if (!человек.вид.яХожу) {
        /* Ждём бота. Если он не сходил за пять попыток — стол встал. */
        let ждали = 0;
        while (!человек.вид.яХожу && !человек.вид.завершена && ждали < 25) {
          await new Promise(function (r) { setTimeout(r, 200); });
          await человек.обновить();
          ждали++;
        }
        if (!человек.вид.яХожу && !человек.вид.завершена) { встал = true; break; }
        continue;
      }
      const { ходы } = ходыИзКартинки(человек.вид.доска, человек.вид.чейХод);
      if (!ходы.length) break;
      const выбран = выбратьХод(ходы);
      const ответ = await человек.ход({
        действие: 'ход', откуда: выбран.откуда, куда: выбран.куда,
        побитые: выбран.побитые, станетДамкой: выбран.станетДамкой
      });
      проверить(ответ.принято === true, 'бот-комната: сервер не принял законный ход — «' + ответ.причина + '»');
      if (!ответ.принято) break;
      ходов++;
    }
    await человек.обновить();
    console.log('  с ботом: ходов человека ' + ходов + ', партия ' +
      (человек.вид.завершена ? 'доиграна' : 'не доиграна'));
    проверить(!встал, 'стол с ботом не встал: бот ходит');
    проверить(человек.вид.завершена === true, 'партия против бота доигралась до конца');
    /* Следов работы бота в ответе быть не должно: ни плана, ни оценки. */
    const весьВид = JSON.stringify(человек.вид);
    проверить(!/оценка|глубина|перебор|план/i.test(весьВид),
      'в ответе видны внутренности бота: ' + весьВид.slice(0, 100));
  }
  await человек.выйти();

  доложить(было);
}

function доложить(было) {
  console.log('');
  console.log('проверок сделано: ' + проверок);
  console.log('ответов сервера осмотрено сторожем: ' + сторож.сколькоОсмотрено());
  if (сторож.новыеПоля.size) {
    console.log('');
    console.log('НОВЫЕ ПОЛЯ В ОТВЕТАХ (' + сторож.новыеПоля.size + '): на утечку не похожи, посмотрите глазами —');
    сторож.новыеПоля.forEach(function (образчик, имя) { console.log('  • «' + имя + '» = ' + образчик); });
  }
  if (провалы.length === 0) {
    console.log('=== Итог: всё сошлось. Партия по сети играется, бои приходят с полным путём, ' +
                'реванш чистит доску, чужого в ответах нет ===');
    return;
  }
  console.log('');
  console.log('!!! НАЙДЕНО ПЛОХОГО: ' + провалы.length);
  Array.from(new Set(провалы)).slice(0, 30).forEach(function (п) { console.log('  - ' + п); });
  process.exitCode = 1;
}

