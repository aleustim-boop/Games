/* Как выбирается ход: ровно так же, как в браузере                    */
/* ------------------------------------------------------------------ */

/**
 * Из присланной картинки доски собрать позицию и спросить у правил,
 * какие ходы законны. Ровно это делает страница на телефоне: своей
 * копии правил у неё нет, и у прогона тоже нет.
 */
function ходыИзКартинки(картинка, чейХод) {
  /* Чей ход — вторым доводом: в картинке доски этого нет вовсе, и без
     него правила посчитали бы ходы всегда за белых. Ровно так же его
     передаёт страница: берёт «чейХод» из ответа сервера. */
  const партия = Правила.партияИзКартинки(картинка, чейХод);
  return { партия: партия, ходы: Правила.возможныеХоды(партия) };
}

/** Выбрать ход. Бои правила и так делают обязательными; из равных берём случайный. */
function выбратьХод(ходы) {
  return ходы[Math.floor(Math.random() * ходы.length)];
}

/** Сколько на доске дамок (заглавные буквы в картинке). */
function дамок(картинка) {
  return картинка.join('').replace(/[^БЧ]/g, '').length;
}

/* ------------------------------------------------------------------ */
/* Одна партия двух живых игроков                                      */
/* ------------------------------------------------------------------ */

async function сыгратьПартию(первый, второй, подпись) {
  const итоги = { ходов: 0, боёв: 0, цепочек: 0, дамокПоявилось: 0, длиннейшаяЦепочка: 0 };
  let дамокБыло = 0;

  for (let шаг = 0; шаг < ПОТОЛОК_ХОДОВ; шаг++) {
    await первый.обновить();
    await второй.обновить();

    // Оба обязаны видеть одну и ту же доску
    проверить(JSON.stringify(первый.вид.доска) === JSON.stringify(второй.вид.доска),
      подпись + ': игроки видят разные доски');
    проверить(первый.вид.завершена === второй.вид.завершена,
      подпись + ': один думает, что партия кончилась, а другой нет');

    if (первый.вид.завершена) return итоги;

    проверить(первый.вид.яХожу !== второй.вид.яХожу,
      подпись + ': ходят оба сразу или никто (ход ' + шаг + ')');

    const ходящий = первый.вид.яХожу ? первый : второй;
    const { партия, ходы } = ходыИзКартинки(ходящий.вид.доска, ходящий.вид.чейХод);
    проверить(ходы.length > 0, подпись + ': ходить нечем, а партия не окончена');
    if (!ходы.length) return итоги;

    /* Сверяем с сервером и признак «есть бой»: страница по нему пишет
       «брать обязательно», и разойтись они не должны. */
    проверить(ходящий.вид.естьБой === Правила.естьБой(партия),
      подпись + ': сервер и правила по-разному считают, есть ли бой');

    const выбран = выбратьХод(ходы);
    /* Считаем у себя, какой станет доска, — до того, как спросим сервер. */
    const своя = Правила.копияПартии(партия);
    const свойХод = Правила.найтиХод(своя, { откуда: выбран.откуда, куда: выбран.куда, побитые: выбран.побитые });
    Правила.сделатьХод(своя, свойХод);
    const ждём = Правила.картинкаПартии(своя);

    const ответ = await ходящий.ход({
      действие: 'ход', откуда: выбран.откуда, куда: выбран.куда,
      побитые: выбран.побитые, станетДамкой: выбран.станетДамкой
    });
    проверить(ответ.принято === true,
      подпись + ': сервер не принял законный ход ' + выбран.откуда + '→' + выбран.куда +
      ' — «' + ответ.причина + '»');
    if (!ответ.принято) return итоги;

    итоги.ходов++;

    const стало = ответ.состояние && ответ.состояние.доска;
    проверить(JSON.stringify(стало) === JSON.stringify(ждём),
      подпись + ': доска сервера разошлась с правилами после хода ' + выбран.откуда + '→' + выбран.куда);

    /* Полный путь боя — то, ради чего он вообще присылается. */
    const пх = ответ.состояние && ответ.состояние.последнийХод;
    проверить(!!пх, подпись + ': сервер не рассказал, каким был последний ход');
    if (пх) {
      проверить(пх.откуда === выбран.откуда && пх.куда === выбран.куда,
        подпись + ': последний ход назван не тем, что сделали');
      проверить(Array.isArray(пх.путь) && пх.путь.length >= 2,
        подпись + ': у хода нет пути');
      if (Array.isArray(пх.путь) && пх.путь.length >= 2) {
        проверить(пх.путь[0] === выбран.откуда && пх.путь[пх.путь.length - 1] === выбран.куда,
          подпись + ': путь начинается или кончается не там: ' + пх.путь.join('→'));
      }
      if (пх.бой) {
        итоги.боёв++;
        проверить(Array.isArray(пх.побитые) && пх.побитые.length > 0,
          подпись + ': бой без единой побитой шашки');
        проверить(пх.путь.length === пх.побитые.length + 1,
          подпись + ': путь боя короче взятий — ' + пх.путь.join('→') +
          ' при ' + (пх.побитые || []).length + ' взятиях (так чужой бой выглядел бы телепортацией)');
        if (пх.побитые.length >= 2) {
          итоги.цепочек++;
          итоги.длиннейшаяЦепочка = Math.max(итоги.длиннейшаяЦепочка, пх.побитые.length);
        }
      }
      /* Цвет ходившего. Ради него всё и затевалось: экран показывает чужой
         бой по шагам, только если знает, чей это был ход. Сверяем с тем,
         кто ходил на самом деле, и с пометкой «мой» — они обязаны сходиться,
         иначе показ снова тихо перестанет работать. */
      if (пх.чей !== undefined) {
        проверить(пх.чей === ходящий.вид.мойЦвет,
          подпись + ': в ходе назван цвет «' + пх.чей + '», а ходил ' + ходящий.вид.мойЦвет);
        проверить(пх.мой === true,
          подпись + ': свой же ход пришёл ходившему как чужой');
        const уСоперника = ходящий === первый ? второй : первый;
        await уСоперника.обновить();
        const чужой = уСоперника.вид.последнийХод;
        проверить(!!чужой && чужой.чей === пх.чей,
          подпись + ': сопернику цвет хода назван иначе — «' + (чужой && чужой.чей) + '»');
        проверить(!!чужой && чужой.мой === false,
          подпись + ': чужой ход помечен сопернику как свой');
        проверить(!!чужой && чужой.чей !== уСоперника.вид.мойЦвет,
          подпись + ': цвет чужого хода совпал с цветом того, кто его получил');
      }

      /* Внутренних имён мест и следов бота в рассказе о ходе быть не должно. */
      const словами = JSON.stringify(пх);
      проверить(!/перв(ый|ого)|втор(ой|ого)|бот/i.test(словами),
        подпись + ': в рассказе о ходе видно внутреннее имя места или бота — ' + словами.slice(0, 80));
    }

    const сталоДамок = дамок(стало || []);
    if (сталоДамок > дамокБыло) итоги.дамокПоявилось += сталоДамок - дамокБыло;
    дамокБыло = сталоДамок;
  }

  проверить(false, подпись + ': партия не кончилась за ' + ПОТОЛОК_ХОДОВ + ' ходов — похоже, встала');
  return итоги;
}

/* ------------------------------------------------------------------ */
/* Отказы: что сервер обязан не принимать                              */
/* ------------------------------------------------------------------ */

async function проверитьОтказы(первый, второй) {
  console.log('\n=== Отказы: чего сервер принимать не должен ===');

  const третий = await запрос('/войти', { код: первый.код });
  проверить(третий.номер === 403 || (третий.данные && третий.данные.ошибка),
    'третьего пустили за доску на двоих (' + третий.номер + ')');
  console.log('  третий за доской: ' + третий.номер + ' «' + ((третий.данные && третий.данные.ошибка) || '') + '»');

  await первый.обновить();
  await второй.обновить();
  const ходящий = первый.вид.яХожу ? первый : второй;
  const ждущий = первый.вид.яХожу ? второй : первый;

  const выдуманный = await ходящий.ход({ действие: 'ход', откуда: 'a1', куда: 'h8' });
  проверить(выдуманный.принято === false, 'сервер принял выдуманный ход a1→h8');
  console.log('  выдуманный ход: «' + выдуманный.причина + '»');
  проверить(typeof выдуманный.причина === 'string' && выдуманный.причина.length > 5,
    'на выдуманный ход сервер ответил без объяснения');

  const неВСвоюОчередь = await ждущий.ход({ действие: 'ход', откуда: 'c3', куда: 'd4' });
  проверить(неВСвоюОчередь.принято === false, 'сервер принял ход не в свою очередь');
  console.log('  ход не в свою очередь: «' + неВСвоюОчередь.причина + '»');

  const карточный = await ходящий.ход({ действие: 'ходить', карта: 0 });
  проверить(карточный.принято === false, 'сервер принял карточное действие в шашечной комнате');
  console.log('  карточное действие в шашках: «' + карточный.причина + '»');
}

