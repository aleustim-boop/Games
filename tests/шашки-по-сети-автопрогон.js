/* =====================================================================
   ШАШКИ ПО СЕТИ — ЦЕЛАЯ ПАРТИЯ ДВУМЯ ЖИВЫМИ ИГРОКАМИ.

   Онлайн-шашки опубликованы, а живьём их никто не играл. Этот прогон
   садится за доску вместо двух человек и играет партию до конца
   обычными запросами по сети — так же, как это делают два телефона.

   Что проверяется:
     1. Партия доигрывается до конца и не встаёт: ходы, бои, дамки, итог.
     2. Ходы считаются ИЗ ПРИСЛАННОЙ ДОСКИ теми же правилами, что и в
        браузере (js/шашки-правила.js). Своих представлений о правилах
        у прогона нет вовсе — иначе он проверял бы себя, а не игру.
     3. После каждого хода доска сервера совпадает с доской, которую мы
        просчитали у себя. Разошлись — значит сервер и браузер разойдутся
        тоже, и это худшая из возможных поломок.
     4. Цепочка боёв приходит ОДНИМ ходом и с полным путём: путь начинается
        там, откуда пошли, кончается там, куда пришли, и в нём столько же
        шагов, сколько взятий. Без пути чужой бой на экране выглядел бы
        телепортацией.
     5. Реванш: доска встаёт в начальное положение, прошлый ход не тянется
        в новую партию.
     6. Отказы словами: третий за доской, выдуманный ход, ход не в свою
        очередь, карточное действие в шашечной комнате.
     7. Чужого в ответах нет — тем же сторожем, что и у дурака
        (tests/сторож-полей.js): ни внутренних имён мест, ни следов бота.
     8. Бот по сети ходит настоящим js/шашки-бот.js, и партия с ним
        доигрывается.

   Запуск (сервер комнат должен быть уже поднят, лучше «--без-памяти»):
       node tests/шашки-по-сети-автопрогон.js            порт 8798
       node tests/шашки-по-сети-автопрогон.js 8790

   Ничего не чинит и в игру не пишет: только играет и считает.
   ===================================================================== */

const http = require('http');
const path = require('path');
const Правила = require(path.join(__dirname, '..', 'js', 'шашки-правила.js'));
const { создатьСторожа } = require('./сторож-полей.js');

const ПОРТ = Number(process.argv[2]) || 8798;
const ХОСТ = '127.0.0.1';

/* Больше этого числа ходов партия в шашки длиться не может: правила сами
   объявляют ничью по бесплодным ходам куда раньше. Упёрлись — значит встали. */
const ПОТОЛОК_ХОДОВ = 400;

const провалы = [];
let проверок = 0;
function проверить(условие, что) {
  проверок++;
  if (!условие) провалы.push(что);
}

const сторож = создатьСторожа(проверить);

/* ------------------------------------------------------------------ */
/* Разговор с сервером                                                 */
/* ------------------------------------------------------------------ */

function запрос(путь, тело, ждатьМс) {
  return new Promise(function (готово, беда) {
    const текст = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const обращение = http.request({
      host: ХОСТ, port: ПОРТ, method: 'POST', path: encodeURI(путь),
      headers: { 'Content-Type': 'application/json', 'Content-Length': текст.length }
    }, function (ответ) {
      let куски = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (к) { куски += к; });
      ответ.on('end', function () {
        let данные = {};
        try { данные = JSON.parse(куски); } catch (сбой) { данные = { сыройОтвет: куски }; }
        готово({ номер: ответ.statusCode, данные: данные });
      });
    });
    обращение.setTimeout(ждатьМс || 15000, function () {
      обращение.destroy(new Error('сервер не ответил на ' + путь + ' вовремя'));
    });
    обращение.on('error', беда);
    обращение.end(текст);
  });
}

function здоровье() {
  return new Promise(function (готово, беда) {
    http.get({ host: ХОСТ, port: ПОРТ, path: encodeURI('/здоровье') }, function (ответ) {
      let к = '';
      ответ.on('data', function (ч) { к += ч; });
      ответ.on('end', function () {
        try { готово(JSON.parse(к)); } catch (сбой) { беда(new Error('сервер ответил не JSON')); }
      });
    }).on('error', беда);
  });
}

/* ------------------------------------------------------------------ */
/* Игрок за доской                                                     */
/* ------------------------------------------------------------------ */

class Игрок {
  constructor(имя, код, пропуск, состояние) {
    this.имя = имя;
    this.код = код;
    this.пропуск = пропуск;
    this.вид = состояние || null;
    if (состояние) сторож.осмотреть(состояние, имя);
  }

  async обновить() {
    const о = await запрос('/состояние', { код: this.код, пропуск: this.пропуск });
    проверить(о.номер === 200, this.имя + ': сервер не отдал состояние (' + о.номер + ')');
    сторож.осмотретьКонверт(о.данные, this.имя);
    this.вид = о.данные.состояние;
    сторож.осмотреть(this.вид, this.имя);
    return this.вид;
  }

  async ход(намерение) {
    const о = await запрос('/ход', Object.assign({ код: this.код, пропуск: this.пропуск }, намерение));
    сторож.осмотретьКонверт(о.данные, this.имя);
    if (о.данные.состояние) {
      this.вид = о.данные.состояние;
      сторож.осмотреть(this.вид, this.имя);
    }
    return о.данные;
  }

  /** Длинный опрос — тот самый путь, которым страница ждёт чужого хода. */
  чтоНового(версия, ждатьМс) {
    return запрос('/что-нового', { код: this.код, пропуск: this.пропуск, версия: версия }, ждатьМс || 40000);
  }

  выйти() { return запрос('/выйти', { код: this.код, пропуск: this.пропуск }); }
}

