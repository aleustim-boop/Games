/* =====================================================================
   ПРОВЕРКА: гонка записи штаб/в-работе.json между хуками «начало» и
   «окончание» исполнителя.

   Беда была настоящая: 26.09 в штаб/в-работе.json провисели три дня две
   мёртвые строки (Explore, «смотритель») — их SubagentStop давно снял бы,
   но не снял. Оба хука (.claude/hooks/начало-исполнителя.js и
   .claude/hooks/по-окончании-исполнителя.js), а из них ещё и
   штаб/в-работе.js, делают одно и то же без защиты: читают файл целиком,
   правят прочитанный объект в памяти, пишут файл целиком обратно. Запусти
   два хука почти одновременно — оба читают одну и ту же старую копию;
   кто пишет последним, стирает чужие правки: воскрешает уже снятую строку
   или теряет только что добавленную.

   Починка — файл-замок рядом (fs.openSync(...,'wx')) и перечитывание
   файла заново уже ПОСЛЕ того как замок получен, плюс запись через
   временный файл + fs.renameSync. Код замка одинаковый в трёх местах:
   .claude/hooks/начало-исполнителя.js, .claude/hooks/по-окончании-исполнителя.js,
   штаб/в-работе.js.

   Работает эта проверка ТОЛЬКО на копии файла во временной папке
   (fs.mkdtempSync) — настоящий штаб/в-работе.json и штаб/права.json не
   трогаются ни на секунду. Оба хука сами понимают путь к файлу и признак
   «без замка» из переменных окружения — но ТОЛЬКО когда эти переменные
   заданы; без них поведение боевое, прежнее.

   Сценарий: 25 записей заводятся по очереди (готовим стартовое состояние,
   не проверяем им гонку), затем ОДНОВРЕМЕННО запускаются десятки процессов:
   половина из первых 25 «заканчивается», плюс ещё 25 новых «начинаются» —
   разом 37 отдельных node-процессов пишут в один файл. В итоге должно
   остаться ровно: вторая половина первых 25 (нетронутая) + все новые 25.
   Ни одной потерянной, ни одной воскрешённой, ни одной задвоенной строки.

   ЗАПУСК
       node tests/в-работе-без-гонки.js
           — обычный прогон: замок включён, требуем чистый итог.

       node tests/в-работе-без-гонки.js --сломать
           — ломающий: тот же сценарий, но с ШТАБ_ПРОВЕРКА_БЕЗ_ЗАМКА=1 (замок
             отключается самими хуками) и небольшой тестовой задержкой между
             чтением и записью (ШТАБ_ПРОВЕРКА_ЗАДЕРЖКА_МС), чтобы окно гонки
             гарантированно открылось. Требует, чтобы итог покраснел — это
             подтверждает, что обычный прогон красит не просто так. Если
             гонку без замка воспроизвести не удалось (такое бывает на очень
             быстрой машине или при малом числе процессов) — проверка честно
             говорит об этом и всё равно завершается с кодом провала: молча
             выдавать такое за успех нельзя.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawn } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const ХУК_НАЧАЛО = path.join(КОРЕНЬ, '.claude', 'hooks', 'начало-исполнителя.js');
const ХУК_ОКОНЧАНИЕ = path.join(КОРЕНЬ, '.claude', 'hooks', 'по-окончании-исполнителя.js');

const ЛОМАЮЩИЙ = process.argv.includes('--сломать');
const РАЗМЕР_ГРУППЫ = 25; // «десятки процессов», как просит задание

/** Номер вида настоящего agentId: буква «a» + 16 шестнадцатеричных знаков. */
function случайныйНомер() {
  let хвост = '';
  for (let i = 0; i < 16; i++) хвост += Math.floor(Math.random() * 16).toString(16);
  return 'a' + хвост;
}

function начатьВход(номер) {
  return {
    tool_name: 'Agent',
    tool_input: {
      subagent_type: 'тест',
      description: 'проверка гонки ' + номер,
      prompt: 'Файлы: tests/фиктивный-' + номер + '.js'
    },
    tool_response: 'Async agent launched successfully. agentId: ' + номер
  };
}
function окончитьВход(номер) {
  return { agent_type: 'тест', status: 'completed', agent_id: номер };
}

/** Запускает хук отдельным процессом: пишет JSON на stdin, ждёт завершения. */
function позватьХук(путьХука, вход, env) {
  return new Promise((готово, отказ) => {
    const проц = spawn(process.execPath, [путьХука], {
      env: Object.assign({}, process.env, env),
      stdio: ['pipe', 'pipe', 'pipe']
    });
    let ошибкаТекст = '';
    // 20 секунд — с запасом сверх собственного ТАЙМАУТ_МС=12000 хука (см. там):
    // хук может честно прождать замок все 12 секунд и бросить ошибку — это
    // не зависание, ответ придёт, просто не сразу.
    const таймер = setTimeout(() => {
      проц.kill();
      отказ(new Error('хук ' + путьХука + ' не ответил за 20 секунд'));
    }, 20000);
    проц.stderr.on('data', (к) => { ошибкаТекст += String(к); });
    проц.on('error', (о) => { clearTimeout(таймер); отказ(о); });
    проц.on('close', () => { clearTimeout(таймер); готово(ошибкаТекст); });
    проц.stdin.write(JSON.stringify(вход));
    проц.stdin.end();
  });
}

/** Номера задач, которые сейчас в файле. null — файл побился и не читается как json. */
function читатьНомера(файл) {
  try {
    const данные = JSON.parse(fs.readFileSync(файл, 'utf8'));
    if (!Array.isArray(данные.работы)) return null;
    return данные.работы.map((р) => р && р.задача);
  } catch (о) {
    return null;
  }
}

/**
 * Весь сценарий разом: готовит копию файла, гоняет хуки, возвращает разбор
 * итога. env-довод — переменные окружения сверх обязательных путей (для
 * ломающего прогона — отключение замка и тестовая задержка).
 */
async function прогонСценария(доп) {
  const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'в-работе-без-гонки-'));
  const файлРабот = path.join(врем, 'в-работе.json');
  const файлПрав = path.join(врем, 'права.json');
  fs.writeFileSync(файлРабот, JSON.stringify({ работы: [] }, null, 2) + '\n', 'utf8');
  fs.writeFileSync(файлПрав, '{}\n', 'utf8');

  const env = Object.assign({
    ШТАБ_ПРОВЕРКА_ФАЙЛ_РАБОТ: файлРабот,
    ШТАБ_ПРОВЕРКА_ФАЙЛ_ПРАВ: файлПрав
  }, доп);

  const проверки = []; // { что, ок }

  try {
    const группаА = Array.from({ length: РАЗМЕР_ГРУППЫ }, случайныйНомер);
    const группаБ = Array.from({ length: РАЗМЕР_ГРУППЫ }, случайныйНомер);
    const серединаА = Math.floor(РАЗМЕР_ГРУППЫ / 2);
    const снятьИзА = группаА.slice(0, серединаА);      // уберём параллельно с добавлением группы Б
    const оставитьИзА = группаА.slice(серединаА);       // должны остаться нетронутыми

    // Готовим стартовое состояние ПОСЛЕДОВАТЕЛЬНО — гонку тут не проверяем,
    // нужна лишь уверенность, что дальше сверяем именно параллельную часть.
    for (const номер of группаА) {
      await позватьХук(ХУК_НАЧАЛО, начатьВход(номер), env);
    }
    const послеПодготовки = читатьНомера(файлРабот) || [];
    const пропалиПриПодготовке = группаА.filter((н) => !послеПодготовки.includes(н));
    проверки.push({
      что: 'последовательная подготовка не потеряла ни одной из ' + РАЗМЕР_ГРУППЫ + ' записей',
      ок: пропалиПриПодготовке.length === 0,
      подробно: пропалиПриПодготовке.length ? 'пропали: ' + пропалиПриПодготовке.join(', ') : ''
    });

    // Параллельно: половину группы А «заканчиваем», группу Б целиком «начинаем» —
    // РАЗМЕР_ГРУППЫ/2 + РАЗМЕР_ГРУППЫ процессов разом на один и тот же файл.
    const параллельно = снятьИзА.map((н) => позватьХук(ХУК_ОКОНЧАНИЕ, окончитьВход(н), env))
      .concat(группаБ.map((н) => позватьХук(ХУК_НАЧАЛО, начатьВход(н), env)));
    const стдерры = await Promise.all(параллельно);

    // 29.09: штаб поймал перемежающийся провал обычного прогона — виновата
    // была именно эта ветка (замок истёк по таймауту и хук писал БЕЗ него).
    // Теперь при истечении таймаута хук не пишет, а бросает ошибку в stderr —
    // проверяем явно, что под этой нагрузкой такого не случилось ни разу;
    // если случилось — красим проверку с понятной причиной, а не гадаем по
    // одним только потерянным/воскрешённым строкам.
    const ошибкиЗамка = стдерры.filter((т) => /не дождались замка/.test(т));
    проверки.push({
      что: 'ни один хук не отказался писать из-за нехватки времени на замок',
      ок: ошибкиЗамка.length === 0,
      подробно: ошибкиЗамка.length ? ошибкиЗамка.length + ' раз(а), например: ' + ошибкиЗамка[0].trim() : ''
    });
    // Диагностика: любой другой текст в stderr тоже подозрителен в обычном
    // режиме — печатаем, чтобы найти настоящую причину потери строки, если
    // она не в таймауте замка (23.09-2 расследование).
    const прочиеОшибки = стдерры.filter((т) => т.trim() && !/не дождались замка/.test(т));
    if (прочиеОшибки.length) {
      console.log('ДИАГНОСТИКА: посторонний stderr от хуков (' + прочиеОшибки.length + '): ' + прочиеОшибки.map((т) => JSON.stringify(т.trim())).join(' | '));
    }

    const итоговые = читатьНомера(файлРабот);
    проверки.push({ что: 'итоговый файл читается как json со списком работ', ок: итоговые !== null });

    if (итоговые !== null) {
      const ожидаемые = оставитьИзА.concat(группаБ);
      const потеряны = ожидаемые.filter((н) => !итоговые.includes(н));
      const воскрешены = снятьИзА.filter((н) => итоговые.includes(н));
      const повторы = итоговые.filter((н, i) => итоговые.indexOf(н) !== i);

      проверки.push({
        что: 'нет потерянных строк (должны были остаться ' + ожидаемые.length + ')',
        ок: потеряны.length === 0,
        подробно: потеряны.length ? потеряны.join(', ') : ''
      });
      проверки.push({
        что: 'нет воскрешённых строк (должны были исчезнуть ' + снятьИзА.length + ' после «окончания»)',
        ок: воскрешены.length === 0,
        подробно: воскрешены.length ? воскрешены.join(', ') : ''
      });
      проверки.push({
        что: 'нет задвоенных строк',
        ок: повторы.length === 0,
        подробно: повторы.length ? повторы.join(', ') : ''
      });
      console.log('ожидалось записей: ' + ожидаемые.length + ', в файле после параллели: ' + итоговые.length);
    }
  } finally {
    try { fs.rmSync(врем, { recursive: true, force: true }); } catch (о) { /* временная папка — не критично */ }
  }

  return проверки;
}

function напечататьИИтог(проверки) {
  let провалов = 0;
  for (const п of проверки) {
    if (п.ок) {
      console.log('  ок   ' + п.что);
    } else {
      провалов++;
      console.log('  ПРОВАЛ: ' + п.что + (п.подробно ? ' — ' + п.подробно : ''));
    }
  }
  console.log('Итого проверок: ' + проверки.length + ', провалов: ' + провалов);
  return провалов;
}

async function основной() {
  if (!ЛОМАЮЩИЙ) {
    console.log('Обычный прогон: замок включён, ' + РАЗМЕР_ГРУППЫ + ' + ' + РАЗМЕР_ГРУППЫ + ' записей, из них половина первой группы параллельно снимается.');
    const проверки = await прогонСценария({});
    const провалов = напечататьИИтог(проверки);
    process.exit(провалов === 0 ? 0 : 1);
    return;
  }

  console.log('Ломающий прогон: замок отключён (ШТАБ_ПРОВЕРКА_БЕЗ_ЗАМКА=1) + тестовая задержка 40мс между чтением и записью.');
  const проверки = await прогонСценария({ ШТАБ_ПРОВЕРКА_БЕЗ_ЗАМКА: '1', ШТАБ_ПРОВЕРКА_ЗАДЕРЖКА_МС: '40' });
  const провалов = напечататьИИтог(проверки);

  if (провалов > 0) {
    console.log('Ломающий прогон ПОКРАСНЕЛ, как и должен, — без замка гонка подтверждена, обычный прогон красит не просто так.');
    process.exit(0);
  }
  console.log('ПРОВАЛ ломающего прогона: даже без замка ни одна строка не потерялась, не воскресла и не задвоилась — гонку на этой машине этим числом процессов воспроизвести не удалось. Честно говорю как есть, а не выдаю за успех.');
  process.exit(1);
}

основной().catch((о) => {
  console.error('ошибка проверки: ' + (о && о.stack || о));
  process.exit(1);
});
