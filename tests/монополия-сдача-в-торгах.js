/* Падение правил внутри сценария — провал, а не обрыв прогона. */
function сценарий(название, тело) {
  console.log('\n--- ' + название + ' ---');
  try {
    тело();
  } catch (e) {
    отметить(false, название + ': правила упали с ошибкой «' + e.message + '»');
  }
}

const own = (g, p, ids, level = 0) =>
  ids.forEach((id) => Object.assign(g.properties[id], { owner: p, level }));
const А = 0, Б = 1, В = 2, Г = 3;

/* Стол: у А, Б, В — по целому кварталу без домов (16-18-19, 6-8-9,
   11-13-14), каждый может построить дом. Ничейные клетки забиты домами
   так, что в банке ровно один дом. Остальные (Г, Д) строить не могут —
   это «не участники» торгов; у Г есть вокзалы 5 и 15 (на них не
   строят, и участником торгов он не становится), чтобы
   после его сдачи было что выставлять на аукцион. Общий ход — у Г, если
   он есть, иначе у А. Домов у А, Б, В нет, поэтому их сдача не
   возвращает здания в банк и торги за «последний» дом не отменяются. */
function стол(n, seed) {
  const g = P.create(n, seed);
  g.turn = n >= 4 ? Г : А;
  g.phase = 'manage';
  g.queue = [];
  own(g, А, [16, 18, 19]);
  own(g, Б, [6, 8, 9]);
  own(g, В, [11, 13, 14]);
  if (n >= 4) own(g, Г, [5, 15]);
  [21, 23, 24, 26, 27, 29, 37].forEach((id) => { g.properties[id].level = 4; });
  g.properties[39].level = 3;
  return g;
}
const МЕСТО = { [А]: 16, [Б]: 6, [В]: 11 };
/* Торги за последний дом: А строит — участники А, Б, В, ход у А.
   Дальше — ходы по списку: число = ставка на своё место, 'пас' — пас. */
function торги(n, seed, ходы) {
  const g = стол(n, seed);
  P.action(g, А, { type: 'build', id: 16 });
  for (const х of ходы) {
    const кто = P.who(g);
    P.action(g, кто, х === 'пас' ? { type: 'pass' } : { type: 'bid', amount: х, id: МЕСТО[кто] });
  }
  return g;
}

/* Два пути выбытия: настоящая сдача и флаг out (партия из памяти,
   оживляется при загрузке — assert). */
const ПУТИ = ['сдача', 'флаг'];
function выбыть(g, p, путь) {
  if (путь === 'сдача') P.action(g, p, { type: 'surrender' });
  else {
    g.players[p].out = true;
    P.assert(g);
  }
}
/* Итог торгов за здание: идут — их состояние; кончились — чем. */
function итог(g) {
  const a = g.auction;
  if (a && a.building)
    return {
      идут: true,
      high: a.high,
      bid: a.bid,
      bids: a.bids,
      targets: a.targets,
      actor: a.actor,
      eligible: a.eligible.slice().sort(),
      passed: a.passed.slice().sort(),
    };
  const победа = g.events.find((e) => e.kind === 'auctionWin');
  return {
    идут: false,
    победа: победа ? { player: победа.player, id: победа.id, amount: победа.amount } : null,
    вБанке: g.events.some((e) => e.kind === 'auctionEmpty' && e.text === 'Здание осталось в банке'),
  };
}
const строка = (x) => JSON.stringify(x);
/* Торги, продолжение которых после выбытия ведёт живой игрок: пасуем за
   всех, кроме того, кто должен победить, пока торги за здание идут. */
function допасовать(g) {
  let шагов = 0;
  while (g.phase === 'auction' && g.auction.building && шагов++ < 20) P.action(g, P.who(g), { type: 'pass' });
}
/* Партия после всех торгов живая: пропасовать чужие аукционы, после
   этого нет аукциона, очередь пуста, assert и who не падают. */
function проверитьЧтоПартияИдёт(g, название) {
  let шагов = 0;
  while (g.phase === 'auction' && шагов++ < 40) P.action(g, P.who(g), { type: 'pass' });
  let ошибка = null;
  try {
    P.assert(g);
    const кто = P.who(g);
    if (g.players[кто].out) throw Error('ход у выбывшего ' + кто);
  } catch (e) {
    ошибка = e;
  }
  отметить(!ошибка && g.phase !== 'auction' && g.queue.length === 0, название + ': партия идёт дальше — торгов нет, очередь пуста, ход у живого (этап «' + g.phase + '»' + (ошибка ? ', упало: ' + ошибка.message : '') + ')');
}

console.log('Проверка: сдача посреди торгов за здание снимает только ставку сдавшегося (правила: ' + ПУТЬ_ПРАВИЛ + (ЛОМАТЬ ? ', это копия' : ', это файл проекта') + ')');

/* Для каждого сценария: исход одинаков у сдачи и у флага (пункт 4). */
function обаПути(название, собрать, кто, проверить) {
  const итоги = {};
  for (const путь of ПУТИ) {
    сценарий(название + ' [' + путь + ']', () => {
      const g = собрать();
      const деньгиДо = g.players[кто].money;
      выбыть(g, кто, путь);
      отметить(g.players[кто].out === true, название + ' [' + путь + ']: выбывший выбыл');
      итоги[путь] = итог(g);
      if (путь === 'флаг') отметить(g.players[кто].money === деньгиДо, название + ' [флаг]: с выбывшего за ставку ничего не списано (' + g.players[кто].money + ')');
      проверить(g, название + ' [' + путь + ']', путь);
    });
  }
  отметить(
    итоги.сдача !== undefined && строка(итоги.сдача) === строка(итоги.флаг),
    название + ': сдача и флаг ведут к одному исходу (' + строка(итоги.сдача) + ' / ' + строка(итоги.флаг) + ')',
  );
}

