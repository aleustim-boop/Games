#!/usr/bin/env node
'use strict';

/**
 * Проверка возврата к незаконченной партии с ботом.
 *
 * Партия сохраняется в память телефона и разбирается обратно.
 * Главное тут — связка очереди (Object.defineProperty) жива после разбора.
 *
 * Команда:
 *   node tests/возврат-к-боту.js [--тестовая-папка=ПУТЬ]
 *
 * Ломающий запуск:
 *   Портит копию js/game.js во временной папке (удаляет связку очереди),
 *   убеждается, что проверка краснеет на этом.
 */

const fs = require('fs');
const path = require('path');
const { spawn } = require('child_process');

/* =====================================================================
   ПАРСИНГ ДОВОДОВ
   ===================================================================== */

function разобратьДоводы() {
  const аргументы = {};
  for (const довод of process.argv.slice(2)) {
    const [ключ, значение] = довод.split('=');
    if (ключ.startsWith('--тестовая-папка')) {
      аргументы.тестоваяПапка = значение;
    }
  }
  return аргументы;
}

const аргументы = разобратьДоводы();
const тестоваяПапка = аргументы.тестоваяПапка;
const проектПапка = path.join(__dirname, '..');

/* =====================================================================
   ЗАГРУЗКА МОДУЛЯ ИГРЫ
   ===================================================================== */

function загрузитьМодульИгры(папка = проектПапка) {
  let путь = path.join(папка, 'js', 'game.js');

  // Если файл не найден по стандартному пути, ищем game.js напрямую в папке
  if (!fs.existsSync(путь) && fs.existsSync(path.join(папка, 'game.js'))) {
    путь = path.join(папка, 'game.js');
  }

  if (!fs.existsSync(путь)) {
    console.error(`ОШИБКА: не найден файл ${путь}`);
    process.exit(1);
  }
  // Очистить кэш, чтобы перезагрузить
  try {
    delete require.cache[require.resolve(путь)];
  } catch (e) {
    // может быть неразрешимым, игнорируем
  }
  return require(путь);
}

let Игра = null;

function инициализироватьИгру() {
  Игра = загрузитьМодульИгры(тестоваяПапка || проектПапка);

  // Проверить, что функции экспортированы
  if (typeof Игра.собратьЗаписьПартии !== 'function') {
    console.error('ОШИБКА: функция собратьЗаписьПартии не найдена в module.exports');
    process.exit(1);
  }
  if (typeof Игра.разобратьЗаписьПартии !== 'function') {
    console.error('ОШИБКА: функция разобратьЗаписьПартии не найдена в module.exports');
    process.exit(1);
  }
}

/* =====================================================================
   ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ
   ===================================================================== */

class Проверка {
  constructor() {
    this.тестов = 0;
    this.провалов = 0;
  }

  утверждение(условие, описание) {
    this.тестов++;
    if (!условие) {
      this.провалов++;
      console.error(`  ✗ ${описание}`);
    }
  }

  равно(получено, ожидалось, описание) {
    const одинаково = JSON.stringify(получено) === JSON.stringify(ожидалось);
    this.утверждение(одинаково, описание +
      (одинаково ? '' : `\n    получено: ${JSON.stringify(получено)}\n    ожидалось: ${JSON.stringify(ожидалось)}`));
  }

  отчёт() {
    console.log(`  Провалов в этом блоке: ${this.провалов}`);
    return { провалы: this.провалов, проверки: this.тестов };
  }
}

/* Сравнить два объекта поле за полем (для поверхностного сравнения) */
function сравнитьПоля(объект1, объект2) {
  const ключи1 = Object.keys(объект1).sort();
  const ключи2 = Object.keys(объект2).sort();
  if (ключи1.length !== ключи2.length) {
    return { совпадают: false, разница: `разное количество полей: ${ключи1.length} vs ${ключи2.length}` };
  }
  for (let i = 0; i < ключи1.length; i++) {
    if (ключи1[i] !== ключи2[i]) {
      return { совпадают: false, разница: `разные имена полей: ${ключи1[i]} vs ${ключи2[i]}` };
    }
  }
  return { совпадают: true };
}

