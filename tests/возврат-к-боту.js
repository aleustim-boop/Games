function проверитьЗащитуОтЗадвоения() {
  console.log('\n[Проверка 6] Запись с задвоенной картой отвергается');
  const проверка = new Проверка();

  // Создать честную партию
  const партия1 = Игра.создатьПартию({
    игроки: ['человек', 'бот'],
    сложность: 'обычный',
    зерно: 333333
  });

  // Собрать запись
  const запись1 = Игра.собратьЗаписьПартии(партия1, 0);
  const текстЗапись = JSON.stringify(запись1);

  // Парсим и портим: задваиваем первую карту руки (копируем её ещё раз)
  const испорченная = JSON.parse(текстЗапись);
  if (испорченная.руки.человек && испорченная.руки.человек.length > 0) {
    // Задвоим первую карту: добавляем вторую копию и убираем что-то из колоды,
    // чтобы общее количество карт осталось прежним
    const картаДляДвоения = испорченная.руки.человек[0];
    испорченная.руки.человек.push(картаДляДвоения);
    // Убираем первую карту из колоды, чтобы общее количество совпало
    if (испорченная.колода.length > 0) {
      испорченная.колода.shift();
    }
  }

  let результатРазбора;
  try {
    результатРазбора = Игра.разобратьЗаписьПартии(JSON.stringify(испорченная));
    проверка.утверждение(результатРазбора === null, 'Запись с задвоенной картой отвергнута (null)');
  } catch (ошибка) {
    проверка.утверждение(false, `Обработка испорченной записи упала: ${ошибка.message}`);
  }

  const итог = проверка.отчёт();
  return итог;
}

