function проверитьДоигрывание() {
  console.log('\n[Проверка 4] Восстановленная партия живая: очередь связана и бот может ходить');
  const проверка = new Проверка();

  // Создать и сразу сохранить партию
  const партия1 = Игра.создатьПартию({
    игроки: ['человек', 'бот'],
    сложность: 'лёгкий',
    зерно: 222222
  });

  // Собрать запись
  const запись1 = Игра.собратьЗаписьПартии(партия1, 0);
  const всегоКарт1 = партия1.колода.length +
    партия1.руки.человек.length + партия1.руки.бот.length +
    партия1.отбой.length +
    партия1.стол.reduce((s, п) => s + (п.защита ? 2 : 1), 0);

  // Восстановить
  const текст = JSON.stringify(запись1);
  const результат = Игра.разобратьЗаписьПартии(текст);
  проверка.утверждение(результат !== null, 'Запись разобрана');
  if (!результат) return проверка.отчёт();

  const партия2 = результат.партия;

  // Проверить, что очередь живая после разбора
  // Попытаемся поменять местоАтаки и убедимся, что имя изменилось
  const исходноеМесто = партия2.местоАтаки;
  const исходноеИмя = партия2.атакует;
  партия2.местоАтаки = (исходноеМесто + 1) % партия2.игроки.length;
  const новоеИмя = партия2.атакует;
  проверка.утверждение(новоеИмя !== исходноеИмя, 'Очередь живая: имя изменилось с местом');

  // Вернуть исходное место
  партия2.местоАтаки = исходноеМесто;
  проверка.утверждение(партия2.атакует === исходноеИмя, 'Очередь живая: имя вернулось');

  // Проверить, что число карт не изменилось
  const всегоКарт2 = партия2.колода.length +
    партия2.руки.человек.length + партия2.руки.бот.length +
    партия2.отбой.length +
    партия2.стол.reduce((s, п) => s + (п.защита ? 2 : 1), 0);
  проверка.утверждение(всегоКарт2 === партия1.размерКолоды,
    `Карты на месте (${всегоКарт2} == ${партия1.размерКолоды})`);

  const итог = проверка.отчёт();
  return итог;
}

