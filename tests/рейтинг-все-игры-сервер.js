function сценарий1СуммаОчков(рейтинг) {
  console.log('\n1. Сумма очков по всем играм = сумме очков в каждой отдельно');

  const срезШашки = рейтинг.срезДляИгрока('шашки', 100001);
  const срезДурак = рейтинг.срезДляИгрока('дурак', 100001);
  const срезШахматы = рейтинг.срезДляИгрока('шахматы', 100001);
  const срезНарды = рейтинг.срезДляИгрока('нарды', 100001);
  const срезГо = рейтинг.срезДляИгрока('го', 100001);

  const ожидаемыеОчки = срезШашки.я.очки + срезДурак.я.очки +
    срезШахматы.я.очки + срезНарды.я.очки + срезГо.я.очки;

  const срезВсе = рейтинг.срезПоВсемИграм(100001);

  проверить(срезВсе && typeof срезВсе === 'object',
    'срез возвращается объектом');
  проверить(срезВсе.яВТаблице === true,
    'ТЕСТОВИК_1 в таблице: яВТаблице = true');
  проверить(срезВсе.я && typeof срезВсе.я.очки === 'number',
    'поле я.очки присутствует и число');

  if (срезВсе.я) {
    проверить(срезВсе.я.очки === ожидаемыеОчки,
      'очки совпадают: ожидали ' + ожидаемыеОчки + ', получили ' + срезВсе.я.очки);
    /* Если взять максимум вместо суммы, это провалит тест. */
    const максимум = Math.max(срезШашки.я.очки, срезДурак.я.очки,
      срезШахматы.я.очки, срезНарды.я.очки, срезГо.я.очки);
    проверить(срезВсе.я.очки !== максимум,
      'не максимум из игр (' + максимум + '), а сумма: ' + срезВсе.я.очки);
  }
}

function сценарий2ИграНеИзСписка(рейтинг) {
  console.log('\n2. Игра, которой нет в списке (го): не теряется в сумме');

  const срезВсе = рейтинг.срезПоВсемИграм(100001);
  const срезГо = рейтинг.срезДляИгрока('го', 100001);

  if (!срезВсе.я || !срезГо.я) {
    проверить(false, 'срезы пусты');
    return;
  }

  /* Го не в списке умолчаний, но её очки должны быть в сумме. */
  проверить(срезВсе.я.очки >= срезГо.я.очки,
    'общий срез включает очки из го (того, что не в списке): ' +
    'всего ' + срезВсе.я.очки + ', го даёт ' + срезГо.я.очки);
}

