/* =====================================================================
   РЕЙТИНГ: общий срез по всем играм в памяти.

   Что проверяем. Функция server/рейтинг.js срезПоВсемИграм(номер)
   возвращает {всего, яВТаблице, я, верхушка, вокругМеня} — срез общего
   рейтинга, в котором очки, победы и партии суммируются по ВСЕМ играм,
   где играл этот игрок.

   Владелец решил дословно: сумма очков по всем играм. При это должны
   работать и игры, которых нет в списке умолчаний (server/игры/умолчания.js):
   рейтинг открывает таблицу игре по её имени как есть, новое имя проходит
   сквозь имяИгры() которая пропускает его как есть, а не только из четырёх
   известных.

   Сценарии:
     1. Сумма очков по всем играм = сумме очков из каждой игры отдельно.
        Главный признак правильности: если взять максимум вместо суммы,
        этот тест провалится.
     2. Игра, которой НЕТ в списке умолчаний (например «го»): очки от неё
        тоже складываются в общую сумму, не теряются и не выбрасываются.
        Это главный сценарий: первая версия функции обходила только
        известныеИгры() и молча теряла очки в неизвестных играх.
     3. Сумма побед по всем играм равна сумме побед из каждой.
     4. Сумма партий по всем играм равна сумме партий из каждой.
     5. Игрок, игравший в одну игру — остаётся в таблице с верным счётом.
     6. Игрок без единой партии: яВТаблице = false, я = null, функция не падает.
     7. Порядок при равных очках воспроизводится одинаково (две подряд пары).
     8. Нет новых полей наружу: ни игры, ни силы, ни других.
     9. Чтение не меняет состояние: файл памяти не меняется после вызова среза.

   ЛОМАЮЩИЙ ЗАПУСК. При --сломать копируем server/рейтинг.js во временную
   папку, испортим копию (меняем суммирование на максимум), подключаем копию
   и гоняем те же сценарии. На ломаной копии они покраснеют. Настоящий файл
   проекта не портим. После прогона копия удаляется.

   Запуск:
       node tests/рейтинг-все-игры-сервер.js

   Ломающий запуск (обязан покраснеть):
       node tests/рейтинг-все-игры-сервер.js --сломать

   Выход 0 — провалов нет, 1 — есть.
   ===================================================================== */

