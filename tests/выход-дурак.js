/* =====================================================================
   ВЫХОД ИЗ ПАРТИИ В ДУРАКЕ (штаб/план-выход-из-партии.md, этап Э3).

   Что проверяет. Строка листа «⋯» во время партии — «Завершить партию»
   через дверь «завершить» общего листа (js/лист-ещё.js), а не своя
   плашка «#экран-выхода», как было раньше. Подписи последствий — те же,
   что были у «спроситьПроВыход» (см. «подписьВыхода» в js/game.js):
   с ботом — «результат не запишется», по сети вдвоём — «друг останется
   за столом один», компанией — «карты доиграет бот». Сдачи в дураке нет
   ни в браузере, ни на сервере — «Завершить» по сети шлёт то же самое
   «оставитьСетевуюПартию» (Сеть.покинутьПартию), что и раньше у «В меню».
   «‹» на столе и стрелка Telegram — общая дверь «нажатьВМеню» — сначала
   пробуют ту же плашку листа (её открывает «спроситьЗавершить()», её
   отдаёт объект, что вернул «ЛистЕщё.подключить(...)», а не сам модуль
   «window.ЛистЕщё»), и только если плашки не нашлось — старый путь.
   Старая плашка «#экран-выхода» остаётся запасным путём и не удаляется.

   Как проверяет. Поднимает НАСТОЯЩИЕ js/лист-ещё.js и js/game.js в одной
   песочнице vm (приём — как в tests/дверь-профиля-дурака.js, документ —
   честный, из tests/поддельный-браузер.js: classList, textContent и
   querySelector ведут себя как в браузере, а не пустышкой). «партия»,
   «режим» и другие переменные верхнего уровня game.js — «let»/«const»,
   свойствами песочницы не становятся, поэтому читаются и пишутся через
   «спросить» (vm.runInContext по тому же контексту).

   Запуск:
       node tests/выход-дурак.js                  — обычный прогон
       node tests/выход-дурак.js --файл <путь>    — тот же набор проверок,
         но js/game.js берётся не с диска проекта, а из файла по указанному
         пути (для ломающего запуска: путь ведёт на испорченную КОПИЮ во
         временной папке, настоящий js/game.js эта проверка не трогает).
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { сделатьДокумент } = require('./поддельный-браузер');

const КОРЕНЬ = path.join(__dirname, '..');
const ПУТЬ_ЛИСТ_ЕЩЁ = path.join(КОРЕНЬ, 'js', 'лист-ещё.js');

function аргумент(имя) {
  const индекс = process.argv.indexOf(имя);
  return индекс !== -1 ? process.argv[индекс + 1] : null;
}

const путьGameJsИзАргумента = аргумент('--файл') || path.join(КОРЕНЬ, 'js', 'game.js');

/* ---------------------------------------------------------------------
   Минимальная разметка стола дурака: ровно те узлы, которых просят
   js/лист-ещё.js и проверяемые куски js/game.js. Остальные сотни id,
   которые трогает game.js при запуске (счёт, витрина, рекорды…),
   получают честную пустышку «на лету» — см. «позволитьЛюбыеId» ниже.
   --------------------------------------------------------------------- */

function построитьРазметку(документ) {
  function узел(тег, id, класс, родитель) {
    const у = документ.createElement(тег);
    if (id) у.id = id;
    if (класс) у.className = класс;
    (родитель || документ.body).appendChild(у);
    return у;
  }

  узел('button', 'кнопка-игра-ещё');
  узел('button', 'кнопка-в-меню');
  узел('button', 'кнопка-в-меню-итог');

  узел('section', 'экран-игры', 'экран');

  const экранВыхода = узел('section', 'экран-выхода', 'экран');
  узел('p', 'подпись-выхода', null, экранВыхода);
  узел('button', 'кнопка-выход-нет', null, экранВыхода);
  узел('button', 'кнопка-выход-да', null, экранВыхода);

  const лист = узел('div', 'лист-игры', 'лист-ещё скрыт');
  узел('div', 'лист-игры-фон', null, лист);

  function строкаЛиста(id, текст, idСостояния, класс) {
    const кнопка = узел('button', id, класс || 'лист-ещё__строка', лист);
    const подпись = документ.createElement('span');
    подпись.className = 'лист-ещё__подпись';
    подпись.textContent = текст;
    кнопка.appendChild(подпись);
    if (idСостояния) {
      const состояние = документ.createElement('span');
      состояние.id = idСостояния;
      состояние.className = 'лист-ещё__значение';
      кнопка.appendChild(состояние);
    }
    return кнопка;
  }

  строкаЛиста('кнопка-лист-игры-меню', 'В меню');
  строкаЛиста('кнопка-лист-игры-правила', 'Как играть');
  строкаЛиста('кнопка-лист-игры-звук', 'Звук', 'лист-игры-звук-состояние');
  строкаЛиста('кнопка-лист-игры-вибрация', 'Вибрация', 'лист-игры-вибрация-состояние', 'лист-ещё__строка скрыт');
  строкаЛиста('кнопка-лист-игры-оформление', 'Оформление');
  строкаЛиста('кнопка-лист-игры-рекорды', 'Рекорды');
  узел('button', null, 'лист-ещё__закрыть', лист);
}

/**
 * Обернуть document.getElementById: не нашли настоящий узел — честная
 * пустышка (рабочие classList/appendChild/querySelector), но НЕ в дереве —
 * «показатьЭкран» (document.querySelectorAll('.экран')) и наши assert'ы
 * через querySelector её не увидят, только сам game.js через getElementById.
 *
 * «неСоздаватьСами» — список id, которые код создаёт САМ по правилу
 * «getElementById(id) || создать-и-запомнить» (js/лист-ещё.js так строит
 * плашку «плашка-завершить» один раз, лениво): такому id пустышку
 * подставлять нельзя — она подменит собой настоящее создание и проверка
 * никогда не увидит настоящую плашку.
 */
function позволитьЛюбыеId(документ, неСоздаватьСами) {
  const оригинал = документ.getElementById;
  const исключения = new Set(неСоздаватьСами || []);
  const пустышки = new Map();
  документ.getElementById = function (id) {
    const найден = оригинал(id);
    if (найден) return найден;
    if (исключения.has(id)) return null;
    if (пустышки.has(id)) return пустышки.get(id);
    const узел = документ.createElement('div');
    узел.id = id;
    пустышки.set(id, узел);
    return узел;
  };
}

/**
 * Поднять js/лист-ещё.js и js/game.js в ОДНОЙ песочнице — как два тега
 * <script> на одной странице: «window.ЛистЕщё» из первого файла виден
 * второму. «опции.сеть: true» подкладывает window.Сеть (шпион, помнит
 * вызовы «покинутьПартию»); window.Рейтинг — всегда шпион (считает
 * «записатьПартию», чтобы поймать нечаянную запись рекорда).
 */
function поднятьДурака(путьGameJs, опции) {
  опции = опции || {};
  const документ = сделатьДокумент();
  построитьРазметку(документ);
  позволитьЛюбыеId(документ, ['плашка-завершить']);

  const журналРейтинг = [];
  const журналСети = [];

  const окно = {
    document: документ,
    addEventListener: function () {},
    removeEventListener: function () {},
    matchMedia: function () { return { matches: false, addEventListener: function () {}, addListener: function () {} }; },
    localStorage: { getItem: function () { return null; }, setItem: function () {}, removeItem: function () {} },
    innerWidth: 390, innerHeight: 844,
    requestAnimationFrame: function (ф) { return setTimeout(ф, 0); },
    cancelAnimationFrame: function (id) { clearTimeout(id); },
    getComputedStyle: function () {
      return { fontSize: '16px', lineHeight: '19.2px', getPropertyValue: function () { return ''; } };
    },
    Рейтинг: {
      готов: true,
      прочитать: function () { return Promise.resolve({}); },
      записатьПартию: function (запись) { журналРейтинг.push(запись); return Promise.resolve(); }
    }
  };
  if (опции.сеть) {
    окно.Сеть = {
      отправитьХод: function () {},
      покинутьПартию: function () { журналСети.push('покинутьПартию'); }
    };
  }

  const песочница = {
    window: окно,
    document: документ,
    localStorage: окно.localStorage,
    navigator: { userAgent: 'тест выход-дурак' },
    console: { log: function () {}, info: function () {}, warn: function () {}, error: function () {} },
    setTimeout: setTimeout, clearTimeout: clearTimeout,
    setInterval: setInterval, clearInterval: clearInterval,
    Math: Math, Date: Date, JSON: JSON, Number: Number, String: String, Array: Array, Object: Object,
    Boolean: Boolean, RegExp: RegExp, Error: Error, isFinite: isFinite, isNaN: isNaN,
    parseInt: parseInt, parseFloat: parseFloat, Map: Map, Set: Set,
    requestAnimationFrame: окно.requestAnimationFrame,
    cancelAnimationFrame: окно.cancelAnimationFrame,
    getComputedStyle: окно.getComputedStyle
  };
  песочница.globalThis = песочница;
  vm.createContext(песочница);
  vm.runInContext(fs.readFileSync(ПУТЬ_ЛИСТ_ЕЩЁ, 'utf8'), песочница, { filename: 'js/лист-ещё.js (выход-дурак)' });
  vm.runInContext(fs.readFileSync(путьGameJs, 'utf8'), песочница, { filename: путьGameJs + ' (выход-дурак)' });

  // «Вернуться к игре» в настоящей игре дальше перерисовывает стол —
  // для минимальной партии в тесте это ни к чему и только грозит
  // упасть на отсутствующих полях. Подменяем игровую «продолжить» на
  // безопасный счётчик: сама проверка — «дверь.продолжить() дошла до
  // игровой «продолжить»", а не то, что рисует настоящий стол.
  vm.runInContext("window.__вызовыПродолжить = 0; продолжить = function () { window.__вызовыПродолжить++; };", песочница);

  return {
    документ: документ,
    журналРейтинг: журналРейтинг,
    журналСети: журналСети,
    /** Прочитать выражение или вызвать функцию верхнего уровня game.js
     *  («партия», «режим» — «let», свойствами песочницы не становятся). */
    спросить: function (выражение) { return vm.runInContext(выражение, песочница); }
  };
}

function подписьСтрокиМеню(документ) {
  const кнопка = документ.getElementById('кнопка-лист-игры-меню');
  const подпись = кнопка && кнопка.querySelector('.лист-ещё__подпись');
  return подпись ? подпись.textContent : null;
}

function текстПлашки(документ) {
  const плашка = документ.getElementById('плашка-завершить');
  const текст = плашка && плашка.querySelector('.плашка-завершить__текст');
  return { плашка: плашка, текст: текст ? текст.textContent : null };
}

/* =======================================================================
   ВЕСЬ НАБОР ПРОВЕРОК ОДНИМ ПРОГОНОМ
   ======================================================================= */
function прогнать(путьGameJs) {
  const строки = [];
  let провалов = 0;

  function проверить(имя, условие, подробности) {
    if (условие) {
      строки.push('OK    ' + имя);
    } else {
      провалов++;
      строки.push('ПЛОХО ' + имя + (подробности ? ' — ' + подробности : ''));
    }
  }

  /* --- 1) Партия с ботом: видна()/текст/пауза, действие не пишет рекорд, «Вернуться» --- */
  let бот = null;
  try {
    бот = поднятьДурака(путьGameJs, {});
    проверить('1) js/лист-ещё.js + js/game.js поднимаются в песочнице (сценарий «с ботом»)', true);
  } catch (сбой) {
    проверить('1) js/лист-ещё.js + js/game.js поднимаются в песочнице (сценарий «с ботом»)', false, сбой.message);
  }
  if (бот) {
    // 1а) Вне партии — видна() ложна, строка листа обычная «В меню».
    бот.спросить("показатьЭкран('экран-лобби')");
    проверить('1а) вне партии: партияИдётДляЗавершения() ложна',
      бот.спросить('партияИдётДляЗавершения()') === false);
    бот.документ.getElementById('кнопка-игра-ещё').click();
    проверить('1а) вне партии: строка листа — «В меню»', подписьСтрокиМеню(бот.документ) === 'В меню');

    // 1б) Партия с ботом идёт — видна() истинна, строка «Завершить партию»,
    // клик ведёт в общую плашку (не в старую «#экран-выхода»), пауза стоит.
    бот.спросить("показатьЭкран('экран-игры')");
    бот.спросить("партия = { завершена: false };");
    проверить('1б) партия с ботом идёт: партияИдётДляЗавершения() истинна',
      бот.спросить('партияИдётДляЗавершения()') === true);
    бот.документ.getElementById('кнопка-игра-ещё').click();
    проверить('1б) строка листа — «Завершить партию»', подписьСтрокиМеню(бот.документ) === 'Завершить партию');
    бот.документ.getElementById('кнопка-лист-игры-меню').click();
    let плашка1б = текстПлашки(бот.документ);
    проверить('1б) плашка «плашка-завершить» открылась', Boolean(плашка1б.плашка) && !плашка1б.плашка.classList.contains('скрыт'));
    проверить('1б) текст плашки — нынешняя подпись «с ботом»',
      плашка1б.текст === 'Партия прервётся, результат не запишется.', 'получено: ' + JSON.stringify(плашка1б.текст));
    проверить('1б) партия поставлена на паузу (флаг «ждёмОтветПроВыход»)', бот.спросить('ждёмОтветПроВыход') === true);
    проверить('1б) старая плашка «#экран-выхода» НЕ показана — двух плашек подряд не бывает',
      !бот.документ.getElementById('экран-выхода').classList.contains('экран--виден'));

    const кнопкаДа1б = плашка1б.плашка && плашка1б.плашка.querySelector('.плашка-завершить__да');
    проверить('1б) в плашке есть кнопка «Завершить»', Boolean(кнопкаДа1б));
    if (кнопкаДа1б) кнопкаДа1б.click();
    проверить('1б) «Завершить» вызвал нынешний выйтиВМеню — партия сброшена', бот.спросить('партия') === null);
    проверить('1б) режим снова «бот»', бот.спросить('режим') === 'бот');
    проверить('1б) рекорд НЕ записан (с ботом обманывать некого — решение штаба)', бот.журналРейтинг.length === 0);
    проверить('1б) плашка снова скрыта', Boolean(плашка1б.плашка) && плашка1б.плашка.classList.contains('скрыт'));

    // 1в) Новая партия с ботом — «Вернуться к игре»: действие НЕ вызвано,
    // пауза снята, дверь.продолжить() реально позвала игровую «продолжить».
    бот.спросить("показатьЭкран('экран-игры')");
    бот.спросить("партия = { завершена: false };");
    бот.спросить('window.__вызовыПродолжить = 0;');
    бот.документ.getElementById('кнопка-игра-ещё').click();
    бот.документ.getElementById('кнопка-лист-игры-меню').click();
    const плашка1в = бот.документ.getElementById('плашка-завершить');
    проверить('1в) плашка открыта перед «Вернуться к игре»', Boolean(плашка1в) && !плашка1в.classList.contains('скрыт'));
    const кнопкаНет1в = плашка1в && плашка1в.querySelector('.плашка-завершить__нет');
    проверить('1в) в плашке есть кнопка «Вернуться к игре»', Boolean(кнопкаНет1в));
    if (кнопкаНет1в) кнопкаНет1в.click();
    проверить('1в) действие завершения НЕ вызвано — партия жива', бот.спросить('партия') !== null);
    проверить('1в) дверь.продолжить() реально позвала игровую «продолжить»',
      бот.спросить('window.__вызовыПродолжить') === 1);
    проверить('1в) пауза снята («ждёмОтветПроВыход» — false)', бот.спросить('ждёмОтветПроВыход') === false);
    проверить('1в) плашка снова скрыта после «Вернуться к игре»',
      Boolean(плашка1в) && плашка1в.classList.contains('скрыт'));
  }

  /* --- 2) По сети: текст последствия свой у пары и у компании, действие
     шлёт то же «Сеть.покинутьПартию», что и раньше «В меню» (сдачи в
     дураке нет — не «сдаться») --- */
  let сеть = null;
  try {
    сеть = поднятьДурака(путьGameJs, { сеть: true });
    проверить('2) поднимается с window.Сеть (сценарий «по сети»)', true);
  } catch (сбой) {
    проверить('2) поднимается с window.Сеть (сценарий «по сети»)', false, сбой.message);
  }
  if (сеть) {
    // 2а) По сети вдвоём.
    сеть.спросить("показатьЭкран('экран-игры')");
    сеть.спросить("режим = 'сеть'; партия = { завершена: false };");
    проверить('2а) по сети вдвоём: партияИдётДляЗавершения() истинна',
      сеть.спросить('партияИдётДляЗавершения()') === true);
    сеть.документ.getElementById('кнопка-игра-ещё').click();
    сеть.документ.getElementById('кнопка-лист-игры-меню').click();
    const плашка2а = текстПлашки(сеть.документ);
    проверить('2а) текст плашки — честная оговорка про поражение при уходе после хода',
      плашка2а.текст === 'Если вы уже ходили — партия засчитается как поражение, победа сопернику.', 'получено: ' + JSON.stringify(плашка2а.текст));
    const кнопкаДа2а = плашка2а.плашка && плашка2а.плашка.querySelector('.плашка-завершить__да');
    if (кнопкаДа2а) кнопкаДа2а.click();
    проверить('2а) «Завершить» ушёл через оставитьСетевуюПартию → Сеть.покинутьПартию (не «сдаться» — в дураке сдачи нет)',
      сеть.журналСети.length === 1 && сеть.журналСети[0] === 'покинутьПартию', 'журналСети: ' + JSON.stringify(сеть.журналСети));
    проверить('2а) партия сброшена, рекорд не тронут',
      сеть.спросить('партия') === null && сеть.журналРейтинг.length === 0);

    // 2б) По сети компанией (свежая партия в том же окне — журнал очищаем).
    сеть.журналСети.length = 0;
    сеть.спросить("показатьЭкран('экран-игры')");
    сеть.спросить("режим = 'сеть'; партия = { завершена: false, застолом: [{}, {}, {}] };");
    проверить('2б) по сети компанией: партияИдётДляЗавершения() истинна',
      сеть.спросить('партияИдётДляЗавершения()') === true);
    сеть.документ.getElementById('кнопка-игра-ещё').click();
    сеть.документ.getElementById('кнопка-лист-игры-меню').click();
    const плашка2б = текстПлашки(сеть.документ);
    проверить('2б) текст плашки — «карты доиграет бот»',
      плашка2б.текст === 'Вы выйдете из партии — ваши карты доиграет бот, остальные продолжат.',
      'получено: ' + JSON.stringify(плашка2б.текст));
    const кнопкаДа2б = плашка2б.плашка && плашка2б.плашка.querySelector('.плашка-завершить__да');
    if (кнопкаДа2б) кнопкаДа2б.click();
    проверить('2б) «Завершить» компанией — тоже Сеть.покинутьПартию, без «сдаться»',
      сеть.журналСети.length === 1 && сеть.журналСети[0] === 'покинутьПартию', 'журналСети: ' + JSON.stringify(сеть.журналСети));
  }

  /* --- 3) «‹» на столе и стрелка Telegram (нажатьВМеню) во время партии:
     та же плашка листа, старая «#экран-выхода» не показывается --- */
  let стрелка = null;
  try {
    стрелка = поднятьДурака(путьGameJs, {});
    проверить('3) поднимается для проверки «‹»/стрелки Telegram', true);
  } catch (сбой) {
    проверить('3) поднимается для проверки «‹»/стрелки Telegram', false, сбой.message);
  }
  if (стрелка) {
    стрелка.спросить("показатьЭкран('экран-игры')");
    стрелка.спросить("партия = { завершена: false };");
    стрелка.спросить('нажатьВМеню()');
    const плашка3 = текстПлашки(стрелка.документ);
    проверить('3а) «‹» на столе (нажатьВМеню) при идущей партии открывает общую плашку листа',
      Boolean(плашка3.плашка) && !плашка3.плашка.classList.contains('скрыт'));
    проверить('3а) старая плашка «#экран-выхода» не открылась — путь один',
      !стрелка.документ.getElementById('экран-выхода').classList.contains('экран--виден'));

    // Системная стрелка Telegram ведёт тем же путём через шагНазадСоЭкрана —
    // проверяем на СВЕЖЕЙ партии в том же окне (прошлую уже закрывать не нужно,
    // плашка просто откроется заново тем же кликом).
    if (плашка3.плашка) плашка3.плашка.querySelector('.плашка-завершить__нет').click();
    стрелка.спросить("шагНазадСоЭкрана('экран-игры')");
    const плашка3б = текстПлашки(стрелка.документ);
    проверить('3б) системная стрелка Telegram (шагНазадСоЭкрана) ведёт туда же',
      Boolean(плашка3б.плашка) && !плашка3б.плашка.classList.contains('скрыт'));
  }

  /* --- 4) Вне партии «‹»/стрелка уходят сразу, без всякой плашки --- */
  let пусто = null;
  try {
    пусто = поднятьДурака(путьGameJs, {});
    проверить('4) поднимается для проверки «вне партии»', true);
  } catch (сбой) {
    проверить('4) поднимается для проверки «вне партии»', false, сбой.message);
  }
  if (пусто) {
    // «партия» и так null сразу после загрузки — свежая песочница.
    пусто.спросить('нажатьВМеню()');
    проверить('4) вне партии: партия и так пуста, «уход» ничего не ломает',
      пусто.спросить('партия') === null);
    проверить('4) вне партии: новая плашка не появилась',
      !пусто.документ.querySelector('#плашка-завершить'));
    проверить('4) вне партии: старая плашка тоже не появилась',
      !пусто.документ.getElementById('экран-выхода').classList.contains('экран--виден'));
  }

  /* --- 5) Текстом: единая точка входа «нажатьВМеню» у «‹» и у стрелки,
     дверь «завершить» с нужными полями передана в подключитьЛистИгры --- */
  const исходник = fs.readFileSync(путьGameJs, 'utf8');
  проверить('5) кнопка «‹» на столе зовёт «нажатьВМеню», не «спроситьПроВыход» напрямую',
    /наКнопку\('кнопка-в-меню', нажатьВМеню\)/.test(исходник));
  проверить('5) стрелка Telegram (шагНазадСоЭкрана) зовёт «нажатьВМеню»',
    /if \(id === 'экран-игры'\) \{ нажатьВМеню\(\); return; \}/.test(исходник));
  проверить('5) «нажатьВМеню» спрашивает именно объект, что вернул ЛистЕщё.подключить (не window.ЛистЕщё)',
    /листЕщёСтола && typeof листЕщёСтола\.спроситьЗавершить === 'function'/.test(исходник));
  проверить('5) дверь «завершить» передана в подключитьЛистИгры',
    /завершить:\s*\{[\s\S]{0,200}действие:\s*выйтиВМеню[\s\S]{0,200}видна:\s*партияИдётДляЗавершения[\s\S]{0,200}текст:\s*подписьВыхода[\s\S]{0,200}пауза:\s*поставитьПаузуДляЗавершения[\s\S]{0,200}продолжить:\s*снятьПаузуДляЗавершения/.test(исходник));

  return { строки: строки, провалов: провалов };
}

