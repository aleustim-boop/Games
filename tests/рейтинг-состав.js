/**
 * Записать старый файл рейтинга БЕЗ поля поСоставу и прочитать его.
 * Проверяет, что загрузчик не падает на старом формате.
 */
function прогонСоСтарымФайломБезПоСоставу() {
  const место = fs.mkdtempSync(path.join(os.tmpdir(), 'старый-рейтинг-без-составу-'));
  const сейчас = new Date();
  const два = (ч) => String(ч).padStart(2, '0');
  const день = сейчас.getFullYear() + '-' + два(сейчас.getMonth() + 1) + '-' + два(сейчас.getDate());
  // Записываем СТАРЫЙ файл БЕЗ поля поСоставу вообще
  fs.writeFileSync(path.join(место, 'рейтинг.json'), JSON.stringify({
    игроки: [{
      игра: 'дурак', номер: 555001, имя: 'СтарыйИгрок', очки: 30, побед: 3,
      ничьих: 0, партий: 5, деньБотов: '', очкиОтБотовЗаДень: 0,
      последняяИгра: день
      // НАМЕРЕННО БЕЗ поСоставу
    }]
  }), 'utf8');

  const код = 'const р=require(' + JSON.stringify(path.join(КОРЕНЬ, 'server', 'рейтинг.js')) + ');' +
    'const было=р.срезДляИгрока("дурак",555001).я.очки;' +
    'р.учестьПартию("дурак",[{номер:555001,этоБот:false,победил:true},' +
    '{номер:555002,этоБот:false,победил:false}]);' +
    'const стало=р.срезДляИгрока("дурак",555001).я.очки;' +
    'console.log(было+" "+стало);';

  const запуск = child_process.spawnSync(process.execPath, ['-e', код], {
    env: Object.assign({}, process.env, { GAMES_DATA: место }),
    encoding: 'utf8'
  });
  return (запуск.stdout || '').trim() || ('не запустилось: ' + (запуск.stderr || '').trim().slice(0, 120));
}

