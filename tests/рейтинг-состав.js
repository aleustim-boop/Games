/* =====================================================================
   РЕЙТИНГ: ОСЬ СЧЁТА ПО СОСТАВУ ИГРОКОВ (личный / парами)

   Что проверяем. В функции учестьПартию (server/рейтинг.js) третья ось
   счёта разделяет партии по составу: личный (двое людей) и парами (2 на 2).
   Как и ось «поПравилу», здесь та же логика:
     - общий счёт остаётся главным и считается как раньше (не меняется);
     - рядом лежит поле «поСоставу» — те же очки, но разложенные на две половины;
     - суточный потолок один на все три среза (общий, по правилу, по составу);
     - партия, у которой состав неизвестен, не должна падать — состав знаем
       всегда (либо явно парами: true, либо по умолчанию личный).

   Проверяем одиннадцать сценариев:

     1) Личная партия (двое людей, у обоих парами: false): очки победителя
        должны попасть и в общий счёт, и в поСоставу.личный.я.очки, а
        поСоставу.парами.я.очки должен остаться 0.

     2) Партия «2 на 2» (четверо людей, парами: true, напарники указаны):
        очки победившей пары должны попасть в общий счёт и в
        поСоставу.парами.я.очки, а поСоставу.личный.я.очки должен остаться 0
        (для игрока, который ни разу не играл вне пар).

     3) Игрок, сыгравший и личную партию, и партию «2 на 2»:
        поСоставу.личный.я.очки + поСоставу.парами.я.очки должно ровно
        совпадать с общим срез.я.очки (не тройная бухгалтерия, а та же сумма
        на двух полках).

     4) Партия «2 на 2» без явного bool в объекте игрока (парами не указано):
        по правилу составИгрока это должно попасть в «личный», а не потеряться
        и не упасть с ошибкой (не как с «поПравилу», где неизвестное правило
        не попадает никуда — с составом такого не бывает).

     5) Партии с ботом (этоБот: true у соперника): очки от бота должны
        раскладываться по поСоставу правильно (личный или парами), как и от
        людей. Общий потолок, вторая система ограничителей не заводится.

     6) Старый файл рейтинга БЕЗ пола поСоставу вовсе: рейтинг.загрузить()
        должен читать его без ошибок. Общий счёт сохраняется, поСоставу
        заводится пустым (не падает).

     7) Проигравший в личной партии и в партии «2 на 2»: 0 очков в обеих
        половинах, но счётчик партий (.партий) в нужной половине всё равно
        увеличивается (партия была сыграна, просто без очков).

   Как проверить, что тест краснеет:
     Если в коде составИгрока формула будет неправильной (например, всегда
     'парами' или всегда 'личный'), то:
       - Тест 1 провалится: личный счёт пойдёт в парами
       - Тест 2 провалится: парный счёт пойдёт в личный
       - Тест 3 провалится: сумма не сойдётся с общим счётом
     Если поСоставу не считаться в учестьПартию вовсе:
       - Тесты 1, 2, 3 провалятся: очки не будут раскладываться
     Если старый файл не загружаться (ошибка на отсутствующем поле):
       - Тест 6 провалится: загрузчик упадёт или ничего не прочитает
     Если проигравший не будет считаться в половинах:
       - Тест 7 провалится: счётчик партий не увеличится

   Запуск: node tests/рейтинг-состав.js
   Выход 0 — провалов нет.
   ===================================================================== */

