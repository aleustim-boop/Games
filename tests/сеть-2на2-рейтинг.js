/* =====================================================================
   СЕТЬ, 2 НА 2, РЕЙТИНГ — живая проверка этапа 5 плана «2 на 2» в дураке.

   Что проверяем. Четыре РЕАЛЬНЫХ сетевых игрока (не боты, не require
   правил напрямую) заходят за один парный стол через настоящие HTTP-двери
   сервера комнат (/создать, /войти, /ход, /состояние — тот же протокол,
   что и у браузера), доигрывают партию простым «первым допустимым ходом»
   до настоящего конца (кто-то стал дураком), а после — сверяют ответ
   двери /рейтинг «было» и «стало». Смотрим не «что-то изменилось», а
   ТОЧНЫЕ числа: общий счёт, срез «сила» и, самое главное для этапов 1-4,
   срез «поСоставу.парами» — это и есть новый функционал, который здесь
   проверяется живой партией, а не подсунутыми вручную данными.

   Точные ожидаемые очки не выдуманы — они вычислены в этом же файле по
   формуле из server/рейтинг.js (функция учестьПартию): победитель получает
   полную цену партии с человеком за каждого живого противника и ПОЛОВИНУ
   той же цены за напарника; проигравший — цену поражения (у людей это 0)
   за каждого. Цену берём из рейтинг.ЦЕНА, а не переписываем числом:
   изменится тариф — тест продолжит считать верно.

   Почему сервер поднят через require, а не отдельным процессом.
   Проверить /рейтинг может только тот, чья подпись initData совпала
   с ключом бота (HMAC от токена, см. ктоПодписал в server/сервер.js).
   Настоящий токен лежит в bot/.env, а трогать секреты тестировщику
   запрещено. У server/сервер.js для этого специально оставлена ОДНА
   щель — «оснасткаДляПроверки» — которая работает только через require
   в своём процессе (по сети до неё не дотянуться). Поэтому сервер здесь
   поднимается require'ом, на свободном порту (слушаем 0 — ОС сама даёт
   не занятый), а не «node server/сервер.js ПОРТ --без-памяти» вторым
   процессом: с тем флагом реальный /рейтинг было бы нечем подписать.
   Игровой протокол при этом настоящий: живые HTTP-запросы на localhost,
   ходы считает сервер по правилам, а не тестовый скрипт напрямую.
   Побочный эффект того же require-подхода — сервер и без флага не пишет
   рейтинг на диск (запись включает только прямой запуск, см. низ
   server/сервер.js), а GAMES_DATA ниже уводит и само чтение в сторону
   от боевых данных владельца — тот же результат, что даёт «--без-памяти».

   ЛОМАЮЩИЙ ЗАПУСК. При --сломать подменяем рейтинг.учестьПартию на
   пустышку ДО того, как её подхватит server/комнаты.js (тот же кэш
   require). Итог партии тогда нигде не оседает: все «выросло на N»
   обязаны разойтись с явью и тест обязан покраснеть. Заодно это
   доказывает, что сравнение идёт не с захардкоженной константой,
   а именно со значением «было» — обмануть тест, вернув нули, нельзя:
   «было» тоже нули, а «стало» тест ждёт строго БОЛЬШЕ, поэтому
   при поломке равенство «было == стало» само подсвечивает провал.

   Запуск:
       node tests/сеть-2на2-рейтинг.js
   Ломающий запуск (обязан покраснеть):
       node tests/сеть-2на2-рейтинг.js --сломать
   ===================================================================== */

