function запрос(порт, путь, тело) {
  return new Promise(function (готово) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const req = http.request({
      host: ХОСТ, port: порт, method: 'POST', path: encodeURI(путь),
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let куски = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (к) { куски += к; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(куски); } catch (е) { разобрано = { разбор: 'не JSON', сырое: куски }; }
        готово({ номер: ответ.statusCode, данные: разобрано });
      });
    });
    req.on('error', function (е) { готово({ номер: 0, данные: { ошибка: String(е.message) } }); });
    req.write(данные);
    req.end();
  });
}

function подписать(поля, токен) {
  const строки = Object.keys(поля)
    .filter(function (к) { return к !== 'hash'; })
    .map(function (к) { return к + '=' + поля[к]; })
    .sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(токен).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}

/* auth_date всегда «сейчас» — initData годна ограниченное время, а партия
   идёт не мгновенно, поэтому строку нельзя приготовить один раз заранее. */
function initDataДля(номер, имя) {
  const поля = {
    query_id: 'AA2N2' + номер,
    user: JSON.stringify({ id: номер, first_name: имя, username: 'игрок' + номер }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  const сподписью = Object.assign({}, поля, { hash: подписать(поля, ТОКЕН_ДЛЯ_ПРОБЫ) });
  return Object.keys(сподписью)
    .map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(сподписью[к]); })
    .join('&');
}

/* --------------------------------------------------------------------
   Живой сетевой игрок: код, пропуск, и три двери — создать/войти,
   ход, рейтинг. Паттерн — тот же, что в tests/сеть-парами-с-выбыванием.js
   (класс «Игрок»), плюс дверь /рейтинг и подпись при каждом запросе.
   -------------------------------------------------------------------- */

class Игрок {
  constructor(порт, tg, имя) {
    this.порт = порт;
    this.tg = tg;
    this.имя = имя;
    this.код = null;
    this.пропуск = null;
    this.вид = null;
  }
  async создать(доп) {
    const тело = Object.assign({ имя: this.имя, initData: initDataДля(this.tg, this.имя) }, доп || {});
    const ответ = await запрос(this.порт, '/создать', тело);
    if (ответ.номер === 200 && ответ.данные.код) {
      this.код = ответ.данные.код;
      this.пропуск = ответ.данные.пропуск;
      this.вид = ответ.данные.состояние;
    }
    return ответ;
  }
  async войти(код) {
    const ответ = await запрос(this.порт, '/войти', {
      код: код, имя: this.имя, initData: initDataДля(this.tg, this.имя)
    });
    if (ответ.номер === 200 && ответ.данные.пропуск) {
      this.код = код;
      this.пропуск = ответ.данные.пропуск;
      this.вид = ответ.данные.состояние;
    }
    return ответ;
  }
  async обновить() {
    const ответ = await запрос(this.порт, '/состояние', { код: this.код, пропуск: this.пропуск });
    if (ответ.номер === 200 && ответ.данные && ответ.данные.состояние) this.вид = ответ.данные.состояние;
    return this.вид;
  }
  async ход(что) {
    const тело = Object.assign({ код: this.код, пропуск: this.пропуск }, что);
    const ответ = await запрос(this.порт, '/ход', тело);
    if (ответ.номер === 200 && ответ.данные) {
      if (ответ.данные.состояние) this.вид = ответ.данные.состояние;
      return ответ.данные;
    }
    return null;
  }
  async рейтинг() {
    const ответ = await запрос(this.порт, '/рейтинг', {
      initData: initDataДля(this.tg, this.имя), игра: 'дурак'
    });
    return ответ.данные;
  }
}

/* Простой игрок: кроет чем может, иначе берёт; ходит первой годной картой.
   Скопировано с tests/сеть-парами-с-выбыванием.js — цель не проверить
   ИИ, а честно доиграть партию до конца настоящими ходами по сети. */
async function походить(игрок) {
  const вид = игрок.вид;
  if (!вид || вид.завершена) return false;

  if (вид.фаза === 'защита') {
    if (вид.могуПеревести) {
      for (let к = 0; к < вид.мояРука.length; к++) {
        const ответ = await игрок.ход({ действие: 'перевести', карта: к });
        if (ответ && ответ.принято) return true;
      }
    }
    for (let п = 0; п < вид.стол.length; п++) {
      if (вид.стол[п].защита) continue;
      for (let к = 0; к < вид.мояРука.length; к++) {
        if (!правила.бьёт(вид.мояРука[к], вид.стол[п].атака, вид.козырь)) continue;
        const ответ = await игрок.ход({ действие: 'отбить', пара: п, карта: к });
        if (ответ && ответ.принято) return true;
      }
    }
    const беру = await игрок.ход({ действие: 'беру' });
    return Boolean(беру && беру.принято);
  }

  for (let к = 0; к < вид.мояРука.length; к++) {
    const ответ = await игрок.ход({ действие: 'ходить', карта: к });
    if (ответ && ответ.принято) return true;
  }
  const бито = await игрок.ход({ действие: 'бито' });
  return Boolean(бито && бито.принято);
}

/* --------------------------------------------------------------------
   Числа рейтинга, вынутые из ответа /рейтинг ровно теми путями, какими
   их собирает server/рейтинг.js — здесь ни одна структура не выдумана
   заново, только прочитана.
   -------------------------------------------------------------------- */

function числаСреза(часть) {
  return {
    очки: часть && часть.я ? часть.я.очки : 0,
    партий: часть && часть.я ? часть.я.партий : 0,
    побед: часть && часть.я ? часть.я.побед : 0
  };
}

function снимокРейтинга(тело) {
  return {
    ок: Boolean(тело && тело.ок),
    узналиВас: Boolean(тело && тело.узналиВас),
    общий: числаСреза(тело),
    парами: числаСреза(тело && тело.поСоставу ? тело.поСоставу.парами : null),
    личный: числаСреза(тело && тело.поСоставу ? тело.поСоставу.личный : null),
    /* У среза силы поле игрока называется «моя», а не «я» (в отличие
       от общего среза и поСоставу) — см. server/сила-игроков.js. */
    сила: {
      партий: (тело && тело.сила && тело.сила.моя) ? тело.сила.моя.партий : 0
    }
  };
}

