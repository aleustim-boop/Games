  for (let и = 0; и < 80; и++) await встать(1000 + и, 'Н' + и);
  /* Ждущие записи очереди тоже убираем: часы вперёд (личности живут 5 минут). */
  промотать(20000);
  const запомнено = шаговПоЛичностям;
