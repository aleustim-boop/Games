  const шаговНаПодборе = шаговПоЛичностям - запомнено;
  проверить(ждёт(ждущий) || ждущий.тело.статус === 'свели', 'Д: Витя встал в очередь');
  проверить(шаговНаПодборе < 10, 'Д: /подбор прошёл по запомненным ожиданиям ' + шаговНаПодборе +
            ' раз(а), а их не меньше ' + личностей + ' (нужно < 10)');

  const до = шаговПоЛичностям;
  await короткийОпрос(ждущий.тело.ключОжидания);
  const шаговНаОпросе = шаговПоЛичностям - до;
  проверить(шаговНаОпросе < 10, 'Е: опрос прошёл по запомненным ожиданиям ' + шаговНаОпросе +
            ' раз(а) (нужно < 10)');
