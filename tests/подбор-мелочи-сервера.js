/* Счётчик шагов по запомненным ожиданиям сервера. Ставим ДО загрузки
   сервера. Нужную Map узнаём по содержимому (значения с полями «кто» и
   «переводной»), а не по имени переменной: переименуют — проверка не
   ослепнет. Обход через for…of считаем по шагам. */
const КАРТЫ_ЛИЧНОСТЕЙ = new WeakSet();
let размерКартыЛичностей = 0;   // наибольший размер карты ожиданий — для страховки
const настоящийSet = Map.prototype.set;
Map.prototype.set = function (ключ, значение) {
  if (значение && typeof значение === 'object' && 'кто' in значение && 'переводной' in значение) {
    КАРТЫ_ЛИЧНОСТЕЙ.add(this);
  }
  const итог = настоящийSet.call(this, ключ, значение);
  if (КАРТЫ_ЛИЧНОСТЕЙ.has(this) && this.size > размерКартыЛичностей) размерКартыЛичностей = this.size;
  return итог;
};
let шаговПоЛичностям = 0;
/* Очередь подбора (Map ключОжидания → запись) узнаём по полям записи. Шаги
   считаем и у for…of, и у forEach — какой обход ни выберут. */
const КАРТЫ_ОЧЕРЕДИ = new WeakSet();
let шаговПоОчереди = 0;
let размерКартыОчереди = 0;
const настоящийSet2 = Map.prototype.set;
Map.prototype.set = function (ключ, значение) {
  if (значение && typeof значение === 'object' && 'ключОжидания' in значение && 'спрошенВ' in значение) {
    КАРТЫ_ОЧЕРЕДИ.add(this);
  }
  const итог = настоящийSet2.call(this, ключ, значение);
  if (КАРТЫ_ОЧЕРЕДИ.has(this) && this.size > размерКартыОчереди) размерКартыОчереди = this.size;
  return итог;
};
const настоящийForEach = Map.prototype.forEach;
Map.prototype.forEach = function (обратный, привязка) {
  if (!КАРТЫ_ОЧЕРЕДИ.has(this)) return настоящийForEach.call(this, обратный, привязка);
  return настоящийForEach.call(this, function (з, к, к2) { шаговПоОчереди++; return обратный.call(this, з, к, к2); }, привязка);
};
const настоящийОбход = Map.prototype[Symbol.iterator];
Map.prototype[Symbol.iterator] = function () {
  const обход = настоящийОбход.call(this);
  const этоОчередь = КАРТЫ_ОЧЕРЕДИ.has(this);
  if (этоОчередь) {
    return {
      next: function () {
        const шаг = обход.next();
        if (!шаг.done) шаговПоОчереди++;
        return шаг;
      },
      [Symbol.iterator]: function () { return this; }
    };
  }
  if (!КАРТЫ_ЛИЧНОСТЕЙ.has(this)) return обход;
  return {
    next: function () {
      const шаг = обход.next();
      if (!шаг.done) шаговПоЛичностям++;
      return шаг;
    },
    [Symbol.iterator]: function () { return this; }
  };
};

