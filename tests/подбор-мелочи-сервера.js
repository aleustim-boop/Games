function спросить(путь, тело, терпениеМс) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    let закончено = false;
    const запрос = http.request({
      host: ХОЗЯИН_АДРЕС, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        if (закончено) return;
        закончено = true;
        clearTimeout(сторож);
        готово({ код: ответ.statusCode, тело: разобрать(текст), оборван: false });
      });
    });
    const сторож = терпениеМс ? setTimeout(function () {
      if (закончено) return;
      закончено = true;
      запрос.destroy();
      готово({ код: 0, тело: {}, оборван: true });
    }, терпениеМс) : null;
    запрос.on('error', function (сбой) {
      if (закончено) return;
      закончено = true;
      clearTimeout(сторож);
      беда(сбой);
    });
    запрос.write(данные);
    запрос.end();
  });
}

