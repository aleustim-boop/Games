const ПАПКА_КОПИЙ = path.join(os.tmpdir(), 'подбор-мелочи-копии-' + process.pid);

function сделатьКопиюСПорчей(порча) {
  let текст = fs.readFileSync(порча.файл, 'utf8');
  const перевод = текст.indexOf('\r\n') !== -1 ? '\r\n' : '\n';
  for (const [было, стало] of порча.замены) {
    const искомое = было.split('\n').join(перевод);
    const сколько = текст.split(искомое).length - 1;
    if (сколько !== 1) порчаНеПрименилась('строка найдена ' + сколько + ' раз, нужно ровно 1:\n' + было);
    const замена = стало.split('\n').join(перевод);
    текст = текст.replace(искомое, function () { return замена; });
  }
  fs.mkdirSync(ПАПКА_КОПИЙ, { recursive: true });
  const путь = path.join(ПАПКА_КОПИЙ, path.basename(порча.файл));
  fs.writeFileSync(путь, текст, 'utf8');
  return путь;
}

function загрузитьКопиюНаМесте(путьКопии, настоящийПуть) {
  const модуль = new Module(настоящийПуть, module);
  модуль.filename = настоящийПуть;
  модуль.paths = Module._nodeModulePaths(path.dirname(настоящийПуть));
  модуль._compile(fs.readFileSync(путьКопии, 'utf8'), настоящийПуть);
  модуль.loaded = true;
  return модуль;
}

