'use strict';

/* =====================================================================
   ШАШКИ ДЛЯ СЕРВЕРА: ЗНАКИ ВНИМАНИЯ НА ОБЩЕМ КАТАЛОГЕ ДУРАКА

   Что проверяем. server/игры/шашки.js зовётся НАПРЯМУЮ, без сети и без
   комнаты — так меньше движущихся частей, и понятнее, кто виноват, когда
   проверка покраснеет.

   Раньше сервер шашек знал только свой каталог js/шашки-знаки.js
   (нумерация 1..33, свои фразы). Панель «Сказать» в браузере теперь
   общая — js/деберц-знаки.js (нумерация 0..37, тот же список, что у
   нард и деберца, владелец просил «эмоции как в дураке»). Эта проверка
   отвечает на четыре вопроса:

     1) ДОГОВОР. У игры есть Игра.знаки {сколько, этоЗнак, этоБросок,
        голосБота} — тот же интерфейс, каким пользуется server/комнаты.js.
        Каталог общий (38 знаков, 0-based), а не старый шашечный (33, с 1).

     2) ПРИЁМ. Общий номер знака (и без цели, и адресный бросок) доходит
        до видДляИгрока как «знакВнимания» — с нужными полями и только
        с ними: номер, порядковый, имя, этоЯ, а у броска ещё цель/вМеня.

     3) ОТКАЗ. Чужой номер (вне каталога 0..37, отрицательный, дробный,
        NaN, строкой, без поля вовсе) до игрока не доезжает — поля
        «знакВнимания» в виде нет.

     4) БОТ ПО СЕТИ МОЛЧИТ. У общего каталога нет знакБота()/бросокБота():
        ходЗаБота обязан вернуть эмоция:null, бросок:null — как у нард.
        Свой голос у бота остался только офлайн, на экране игры.

   Запуск:
       node tests/шашки-сервер-знаки.js

   ЛОМАЮЩИЙ ЗАПУСК (проверка обязана уметь краснеть):
       node tests/шашки-сервер-знаки.js --сломать

   Копирует server/игры/шашки.js во временную папку и в копии откатывает
   require общего каталога обратно на старый js/шашки-знаки.js — ровно
   та регрессия, которую могли бы случайно вернуть: сервер снова считает
   номера по-старому (с единицы), а панель «Сказать» шлёт общий 0-based
   номер. Проверка обязана покраснеть на приёме такого номера. Файл
   проекта при этом не трогается ни на минуту.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ПУТЬ_ИГРЫ = path.join(КОРЕНЬ, 'server', 'игры', 'шашки.js');
const ПУТЬ_ПРАВИЛ = path.join(КОРЕНЬ, 'js', 'шашки-правила.js');
const ПУТЬ_БОТА = path.join(КОРЕНЬ, 'js', 'шашки-бот.js');
const ПУТЬ_СТАРЫХ_ЗНАКОВ = path.join(КОРЕНЬ, 'js', 'шашки-знаки.js');
const ПУТЬ_ПАРТИИ_ПО_СЕТИ = path.join(КОРЕНЬ, 'server', 'партия-по-сети.js');

const БЕЛЫЕ_МЕСТО = 'первый';
const ЧЁРНЫЕ_МЕСТО = 'второй';

/* Числа общего каталога (js/деберц-знаки.js): 12 эмоций + 11 фраз + 15
   бросков = 38 знаков, нумерация с нуля. Первый бросок — под номером 23. */
const СКОЛЬКО_ЗНАКОВ_ОБЩИХ = 38;
const ПЕРВЫЙ_БРОСОК_ОБЩИЙ = 23;

/* --- счёт проверок --- */
let всегоПроверок = 0;
let провалов = 0;
const красные = [];

function проверить(условие, слова) {
  всегоПроверок++;
  if (условие) {
    console.log('  ок    — ' + слова);
  } else {
    провалов++;
    красные.push(слова);
    console.log('  ПЛОХО — ' + слова);
  }
}

/** Новый стол на двоих: играть незачем, знакам партия не нужна вовсе. */
function накрытьСтол(Игра) {
  return Игра.раздать(БЕЛЫЕ_МЕСТО, { игроки: [БЕЛЫЕ_МЕСТО, ЧЁРНЫЕ_МЕСТО] });
}

/* Поля, которые вид разрешает у знака внимания. У шашек нет «от»/«кому»
   (это только у нард — там знак летит через доску по креслам): здесь
   только «этоЯ» и, для адресного броска, «цель»/«вМеня». */
const ПОЛЯ_ЗНАКА = ['номер', 'порядковый', 'имя', 'этоЯ', 'цель', 'вМеня'];

/* Знака может не быть вовсе (например в ломающем прогоне, где видДляИгрока
   упал внутри себя) — тогда «лишних полей» считаем как есть, отдельной
   строкой, а не роняем проверку исключением при чтении несуществующего
   объекта. */
function лишниеПоляЗнака(знак) {
  if (!знак) return ['(знака нет вовсе)'];
  return Object.keys(знак).filter(function (поле) { return ПОЛЯ_ЗНАКА.indexOf(поле) === -1; });
}

/** Имена полей знака словами — для текста проверки, без падения на undefined. */
function поляЗнакаСловами(знак) {
  return знак ? Object.keys(знак).join(', ') : '(знака нет вовсе)';
}

/* Позвать функцию безопасно: в ломающем прогоне старый каталог может не
   знать современных имён методов («сколько» вместо «сколькоЗнаков») —
   тогда «Игра.знаки.сколько» вовсе не функция, и без этой обёртки один
   упавший вызов уронил бы весь прогон вместо того, чтобы стать красной
   строкой в отчёте. */
function позвать(функция, запасное) {
  try { return функция(); } catch (е) { return запасное; }
}

/* Вид для игрока безопасно: видДляИгрока() в шашки.js сам зовёт
   Знаки.сколько() (поле «знакиВниманияЕсть») — в ломающем прогоне со
   старым каталогом это тоже брошенное исключение, а не просто другое
   значение. Пустой объект вместо вида даёт честные красные строки
   дальше (все поля вида — undefined), а не роняет весь прогон. */
function вид(Игра, партия, ктоЯ, добавка) {
  return позвать(function () { return Игра.видДляИгрока(партия, ктоЯ, добавка); }, {});
}

/* =====================================================================
   ЧАСТЬ 1. ДОГОВОР: ИНТЕРФЕЙС «ЗНАКИ» — ОБЩИЙ КАТАЛОГ, БОТ МОЛЧИТ
   ===================================================================== */

function проверитьДоговор(Игра) {
  console.log('\n--- Договор: знаки — общий каталог дурака ---');

  let беда = '';
  try {
    const реестр = require(path.join(КОРЕНЬ, 'server', 'игры', 'реестр.js'));
    реестр.проверитьДоговор(Игра, 'server/игры/шашки.js');
  } catch (сбой) { беда = сбой.message; }
  проверить(беда === '', 'реестр принимает договор игры' + (беда ? ': ' + беда : ''));

  const сколько = позвать(function () { return Игра.знаки.сколько(); }, NaN);
  проверить(сколько === СКОЛЬКО_ЗНАКОВ_ОБЩИХ,
    'знаков ровно ' + СКОЛЬКО_ЗНАКОВ_ОБЩИХ + ' — общий каталог дурака (пришло ' + сколько + ')');
  /* Номер 0 — маркер перехода на 0-based нумерацию: в старом шашечном
     каталоге счёт шёл с единицы, и нулевой знак был невалиден. */
  проверить(позвать(function () { return Игра.знаки.этоЗнак(0); }, null) === true,
    'знак номер 0 валиден — каталог нумерует с нуля, как у дурака');
  проверить(позвать(function () { return Игра.знаки.этоЗнак(СКОЛЬКО_ЗНАКОВ_ОБЩИХ - 1); }, null) === true,
    'последний знак каталога (' + (СКОЛЬКО_ЗНАКОВ_ОБЩИХ - 1) + ') валиден');
  проверить(позвать(function () { return Игра.знаки.этоЗнак(СКОЛЬКО_ЗНАКОВ_ОБЩИХ); }, null) === false,
    'знак за пределами каталога (' + СКОЛЬКО_ЗНАКОВ_ОБЩИХ + ') невалиден');
  проверить(позвать(function () { return Игра.знаки.этоБросок(ПЕРВЫЙ_БРОСОК_ОБЩИЙ); }, null) === true,
    'первый бросок каталога (' + ПЕРВЫЙ_БРОСОК_ОБЩИЙ + ') распознан как бросок');
  проверить(позвать(function () { return Игра.знаки.этоБросок(ПЕРВЫЙ_БРОСОК_ОБЩИЙ - 1); }, null) === false,
    'знак перед первым броском (' + (ПЕРВЫЙ_БРОСОК_ОБЩИЙ - 1) + ') броском не считается');

  /* Бот по сети молчит: у общего каталога нет знакБота()/бросокБота(),
     поэтому голосБота обязан отдавать null при любом входе. */
  [null, undefined, { эмоция: 0 }, { бросок: { номер: ПЕРВЫЙ_БРОСОК_ОБЩИЙ, цель: ЧЁРНЫЕ_МЕСТО } }]
    .forEach(function (вход) {
      проверить(позвать(function () { return Игра.знаки.голосБота(вход); }, 'исключение') === null,
        'голосБота(' + JSON.stringify(вход) + ') молчит (null)');
    });
}

/* =====================================================================
   ЧАСТЬ 2. ПРИЁМ: ОБЩИЙ НОМЕР ДОХОДИТ ДО ИГРОКА КАК НУЖНЫЙ ЗНАК
   ===================================================================== */

function проверитьПриём(Игра) {
  console.log('\n--- Приём: общий номер доходит в видДляИгрока ---');
  const партия = накрытьСтол(Игра);

  /* а) Свой знак без цели (эмоция под номером 0) — отправитель видит
        «этоЯ: true», сосед — «этоЯ: false», лишних полей нет. */
  const свойЗнак = { номер: 0, порядковый: 1, имя: 'Аня', кто: БЕЛЫЕ_МЕСТО };
  const видБелыхСвой = вид(Игра, партия, БЕЛЫЕ_МЕСТО, { знакСырой: свойЗнак });
  const видЧёрныхСвой = вид(Игра, партия, ЧЁРНЫЕ_МЕСТО, { знакСырой: свойЗнак });
  проверить(Boolean(видБелыхСвой.знакВнимания) &&
    видБелыхСвой.знакВнимания.номер === 0 && видБелыхСвой.знакВнимания.порядковый === 1 &&
    видБелыхСвой.знакВнимания.имя === 'Аня' && видБелыхСвой.знакВнимания.этоЯ === true,
    'приём: свой знак (номер 0) доехал с «этоЯ: true»');
  проверить(Boolean(видЧёрныхСвой.знакВнимания) && видЧёрныхСвой.знакВнимания.этоЯ === false,
    'приём: сосед видит тот же знак с «этоЯ: false»');
  проверить(лишниеПоляЗнака(видБелыхСвой.знакВнимания).length === 0,
    'приём: в объекте знака нет лишних полей (пришло: ' +
    поляЗнакаСловами(видБелыхСвой.знакВнимания) + ')');

  /* б) Адресный бросок — цель и «вМеня» считаются относительно того,
        кто СМОТРИТ, а не того, кто бросок послал. */
  const бросок = {
    номер: ПЕРВЫЙ_БРОСОК_ОБЩИЙ, порядковый: 2, имя: 'Аня', кто: БЕЛЫЕ_МЕСТО,
    цель: ЧЁРНЫЕ_МЕСТО, имяЦели: 'Витя'
  };
  const видБелыхБросок = вид(Игра, партия, БЕЛЫЕ_МЕСТО, { знакСырой: бросок });
  const видЧёрныхБросок = вид(Игра, партия, ЧЁРНЫЕ_МЕСТО, { знакСырой: бросок });
  проверить(видБелыхБросок.знакВнимания && видБелыхБросок.знакВнимания.цель === 'Витя' &&
    видБелыхБросок.знакВнимания.вМеня === false,
    'приём: бросающий видит цель по имени, сам не цель');
  проверить(видЧёрныхБросок.знакВнимания && видЧёрныхБросок.знакВнимания.вМеня === true,
    'приём: адресат видит «вМеня: true»');
  проверить(лишниеПоляЗнака(видЧёрныхБросок.знакВнимания).length === 0,
    'приём: в объекте броска нет лишних полей (пришло: ' +
    поляЗнакаСловами(видЧёрныхБросок.знакВнимания) + ')');
}

/* =====================================================================
   ЧАСТЬ 3. ОТКАЗ: ЧУЖОЙ ИЛИ НЕСУЩЕСТВУЮЩИЙ НОМЕР ДО ИГРОКА НЕ ДОЕЗЖАЕТ
   ===================================================================== */

function проверитьОтказы(Игра) {
  console.log('\n--- Отказ: чужому номеру не верим ---');
  const партия = накрытьСтол(Игра);

  /* Мусорные номера — среди них и валидные номера старого шашечного
     каталога (33 их максимум), которые в общем каталоге тоже могут
     что-то значить, поэтому берём заведомо чужие: далеко за пределами
     общего диапазона 0..37, отрицательные, дробные, NaN, строкой. */
  [999, -1, 3.5, NaN, '0', undefined, СКОЛЬКО_ЗНАКОВ_ОБЩИХ].forEach(function (плохойНомер) {
    const плохой = { номер: плохойНомер, порядковый: 1, кто: БЕЛЫЕ_МЕСТО };
    const пришедшийВид = вид(Игра, партия, ЧЁРНЫЕ_МЕСТО, { знакСырой: плохой });
    проверить(пришедшийВид.знакВнимания === undefined,
      'отказ: недопустимый номер (' + JSON.stringify(плохойНомер) + ') не доехал до игрока');
  });

  /* Обычный ход без знака вовсе — самый частый случай, подделывать
     здесь нечего, поля «знакВнимания» в виде тоже быть не должно. */
  const видБезЗнака = вид(Игра, партия, БЕЛЫЕ_МЕСТО, {});
  проверить(видБезЗнака.знакВнимания === undefined,
    'отказ: без знакСырого поля «знакВнимания» в виде нет вовсе');

  /* Чужое авторство: «кто» не совпадает ни с одним из играющих. Знак
     всё равно валиден по номеру, но виден обоим как ЧУЖОЙ, не свой. */
  const чужойЗнак = { номер: 2, порядковый: 1, имя: 'Кто-то', кто: 'посторонний-игрок' };
  const видБелыхЧужой = вид(Игра, партия, БЕЛЫЕ_МЕСТО, { знакСырой: чужойЗнак });
  const видЧёрныхЧужой = вид(Игра, партия, ЧЁРНЫЕ_МЕСТО, { знакСырой: чужойЗнак });
  проверить(видБелыхЧужой.знакВнимания && видБелыхЧужой.знакВнимания.этоЯ === false &&
    видЧёрныхЧужой.знакВнимания && видЧёрныхЧужой.знакВнимания.этоЯ === false,
    'отказ: подделанный отправитель «этоЯ: false» у обоих игроков');
}

/* =====================================================================
   ЧАСТЬ 4. БОТ ПО СЕТИ МОЛЧИТ И НА НАСТОЯЩЕМ ХОДЕ
   ===================================================================== */

function проверитьБотМолчит(Игра) {
  console.log('\n--- Бот по сети молчит ---');
  const партия = накрытьСтол(Игра);
  const сделано = Игра.ходЗаБота(партия, БЕЛЫЕ_МЕСТО, 'лёгкий');
  проверить(Boolean(сделано), 'бот сходил первым ходом (белые начинают)');
  if (сделано) {
    проверить(сделано.эмоция === null && сделано.бросок === null,
      'ход бота по сети без знака: эмоция:null, бросок:null (пришло ' +
      JSON.stringify({ эмоция: сделано.эмоция, бросок: сделано.бросок }) + ')');
  }
}

/* =====================================================================
   ПРОГОН ЦЕЛИКОМ
   ===================================================================== */

function прогнать(Игра) {
  проверитьДоговор(Игра);
  проверитьПриём(Игра);
  проверитьОтказы(Игра);
  проверитьБотМолчит(Игра);
}

function напечататьИтог() {
  console.log('\nИтого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
}

/* ---------------------------------------------------------------------
   ОБЫЧНЫЙ ЗАПУСК
   --------------------------------------------------------------------- */
function обычныйЗапуск() {
  console.log('=== Шашки для сервера: знаки внимания на общем каталоге дурака ===');
  const Игра = require(ПУТЬ_ИГРЫ);
  прогнать(Игра);
  напечататьИтог();

  if (всегоПроверок === 0) {
    console.log('ПЛОХО: не сделано ни одной проверки — она смотрит не туда');
    process.exitCode = 1;
    return;
  }
  if (провалов > 0) process.exitCode = 1;
  else console.log('Сервер шашек принимает общие знаки внимания и молчит ботом по сети.');
}

/* ---------------------------------------------------------------------
   ЛОМАЮЩИЙ ЗАПУСК: портим КОПИЮ модуля во временной папке — откатываем
   require общего каталога на старый шашечный. Файл проекта не трогаем
   и не откатываем — в нём может лежать чужая несохранённая работа.
   --------------------------------------------------------------------- */
function ломающийЗапуск() {
  console.log('=== Ломающий запуск: в копии модуля откат на старый каталог знаков ===\n');

  const исходник = fs.readFileSync(ПУТЬ_ИГРЫ, 'utf8');

  /* Регрессия: сервер снова require'ит свой старый каталог вместо
     общего. Замена должна быть одна: ноль — ломать нечего, больше
     одной — задели не то место. */
  const былОбщийКаталог = "const Знаки = require('../../js/деберц-знаки.js');";
  const сталоСтарым = "const Знаки = require('../../js/шашки-знаки.js');";
  const числоЗамен = исходник.split(былОбщийКаталог).length - 1;
  if (числоЗамен !== 1) {
    console.log('ПЛОХО: строка подключения общего каталога знаков нашлась ' +
      числоЗамен + ' раз(а) — должно быть ровно один.');
    console.log('       Искали строку: ' + былОбщийКаталог);
    process.exitCode = 2;
    return;
  }
  let порченый = исходник.split(былОбщийКаталог).join(сталоСтарым);

  /* Копия лежит в другой папке — соседние файлы надо звать по полному
     пути, иначе она просто не загрузится. Это не поломка, а переезд. */
  const переезды = [
    ["require('../../js/шашки-правила.js')", 'require(' + JSON.stringify(ПУТЬ_ПРАВИЛ.replace(/\\/g, '/')) + ')'],
    ["require('../../js/шашки-бот.js')", 'require(' + JSON.stringify(ПУТЬ_БОТА.replace(/\\/g, '/')) + ')'],
    ["require('../../js/шашки-знаки.js')", 'require(' + JSON.stringify(ПУТЬ_СТАРЫХ_ЗНАКОВ.replace(/\\/g, '/')) + ')'],
    ["require('../партия-по-сети.js')", 'require(' + JSON.stringify(ПУТЬ_ПАРТИИ_ПО_СЕТИ.replace(/\\/g, '/')) + ')']
  ];
  for (const [было, стало] of переезды) {
    if (порченый.indexOf(было) === -1) {
      console.log('ПЛОХО: в модуле не нашлась строка подключения: ' + было);
      process.exitCode = 1;
      return;
    }
    порченый = порченый.split(было).join(стало);
  }

  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'шашки-сервер-знаки-'));
  const копия = path.join(папка, 'шашки.js');
  try {
    fs.writeFileSync(копия, порченый, 'utf8');
    console.log('  порченая копия: ' + копия + '\n');
    const Порченая = require(копия);
    прогнать(Порченая);
    напечататьИтог();

    const проНольНевалиден = красные.some(function (слова) {
      return слова.indexOf('свой знак (номер 0) доехал') !== -1;
    });
    const проСколько = красные.some(function (слова) {
      return слова.indexOf('знаков ровно ' + СКОЛЬКО_ЗНАКОВ_ОБЩИХ) !== -1;
    });
    if (проНольНевалиден && проСколько) {
      console.log('\nЛомающий запуск покраснел, как и должен. Красные пункты:');
      красные.forEach(function (слова) { console.log('   ' + слова); });
    } else {
      if (!проНольНевалиден) {
        console.log('\nПЛОХО: порченый модуль принял общий номер 0 через старый каталог — проверка смотрит не туда');
      }
      if (!проСколько) {
        console.log('ПЛОХО: порченый модуль не выдал расхождение в числе знаков — проверка смотрит не туда');
      }
      process.exitCode = 1;
    }
  } finally {
    /* Прибираем за собой: сначала файл, потом пустую папку. Ничего
       рекурсивного — сносить папки целиком в проекте запрещено. */
    try { fs.unlinkSync(копия); } catch (е) { /* уже нет — и ладно */ }
    try { fs.rmdirSync(папка); } catch (е) { /* уже нет — и ладно */ }
  }
}

if (process.argv.indexOf('--сломать') !== -1) ломающийЗапуск();
else обычныйЗапуск();
