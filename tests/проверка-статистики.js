'use strict';

/* Проверка статистики партий на своём сервере (порт 8799; рабочий 8790
   не трогаем). Все числа считаются по настоящим HTTP-запросам, а потом
   сверяются с тем, что отдаёт дверь GET /статистика.

   Сценарии:
     А. Двое из Telegram, второй — по приглашению; после раздачи второй
        выходит → партия брошена (уход соперника).
     Б. Тот же первый человек создаёт ещё комнату, сажает бота, начинает,
        выходит → партия с ботом, брошена (комнату убрали).
     В. Парный стол: хозяин + три бота, начали, вышел → парная, с ботами.
     Г. Сетевой автопрогон (дочерний процесс) доигрывает 8 партий по картам.
   Затем: сводки 7/30 дней равны сегодняшней, файл пишется и читается
   обратно другим процессом, выдуманные числа убираются. */

const path = require('path');
const crypto = require('crypto');
const { spawn } = require('child_process');

/* Дочерний процесс — асинхронно, а не spawnSync: сервер живёт в этом же
   процессе, и синхронное ожидание заморозило бы его на всё время прогона. */
function запуститьИДождаться(доводы) {
  return new Promise(function (готово) {
    const дитя = spawn('node', доводы, { encoding: 'utf8' });
    let вывод = '';
    дитя.stdout.on('data', function (кусок) { вывод += кусок; });
    дитя.stderr.on('data', function (кусок) { вывод += кусок; });
    дитя.on('close', function () { готово(вывод); });
  });
}

const КОРЕНЬ = require('path').resolve(__dirname, '..');   // корень проекта — от этого файла, а не зашитый
const сервер = require(path.join(КОРЕНЬ, 'server/сервер.js'));
const статистика = require(path.join(КОРЕНЬ, 'server/статистика.js'));
const знакомые = require(path.join(КОРЕНЬ, 'server/знакомые.js'));

const ПОРТ = 8799;
const АДРЕС = 'http://127.0.0.1:' + ПОРТ;

const токен = (сервер.прочитатьНастройки().BOT_TOKEN || '').trim();
if (!токен) { console.log('НЕТ ТОКЕНА — проверка не пойдёт.'); process.exit(2); }

function подписать(кто) {
  const поля = new URLSearchParams();
  поля.set('user', JSON.stringify(кто));
  поля.set('auth_date', String(Math.floor(Date.now() / 1000)));
  const строки = [];
  for (const пара of поля) строки.push(пара[0] + '=' + пара[1]);
  строки.sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(токен).digest();
  поля.set('hash', crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex'));
  return поля.toString();
}
const аня = подписать({ id: 900001, first_name: 'Аня' });
const боря = подписать({ id: 900002, first_name: 'Боря' });

function стук(путь, тело) {
  return fetch(АДРЕС + путь, {
    method: 'POST', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(тело || {})
  }).then(function (о) { return о.json(); });
}
function спросить(путь) {
  return fetch(АДРЕС + путь).then(function (о) { return о.json(); });
}
const спать = function (мс) { return new Promise(function (f) { setTimeout(f, мс); }); };

let всёХорошо = true;
function проверить(что, правда) {
  console.log((правда ? '  ок   ' : '  БЕДА ') + что);
  if (!правда) всёХорошо = false;
}

async function пройти() {
  // Запись на диск нам нужна: проверяем, что файл переживает перезапуск.
  статистика.включитьЗапись();
  знакомые.включитьЗапись();
  статистика.забытьВсё();
  знакомые.забытьВсё();

  // А. Двое, второй по приглашению, второй выходит.
  const а = await стук('/создать', { initData: аня, имя: 'Аня' });
  const б = await стук('/войти', { код: а.код, initData: боря, имя: 'Боря', поПриглашению: true });
  проверить('А: карты розданы', б.состояние && б.состояние.этап === 'игра');
  await стук('/выйти', { код: а.код, пропуск: б.пропуск });
  await стук('/выйти', { код: а.код, пропуск: а.пропуск });

  // Б. Аня снова создаёт, сажает бота, начинает, выходит.
  const б1 = await стук('/создать', { initData: аня, имя: 'Аня', мест: 2 });
  await стук('/ход', { код: б1.код, пропуск: б1.пропуск, действие: 'бот' });
  const начали = await стук('/ход', { код: б1.код, пропуск: б1.пропуск, действие: 'начать' });
  проверить('Б: партия с ботом началась', начали.принято === true);
  await стук('/выйти', { код: б1.код, пропуск: б1.пропуск });

  // В. Парный стол: хозяин + три бота.
  const в = await стук('/создать', { initData: боря, имя: 'Боря', мест: 4, парами: true });
  for (let н = 0; н < 3; н++) await стук('/ход', { код: в.код, пропуск: в.пропуск, действие: 'бот' });
  const началиПарами = await стук('/ход', { код: в.код, пропуск: в.пропуск, действие: 'начать' });
  проверить('В: парная партия началась', началиПарами.принято === true);
  await стук('/выйти', { код: в.код, пропуск: в.пропуск });

  // Промежуточная сверка — до автопрогона.
  const до = await спросить('/статистика');
  console.log('  до автопрогона: ' + JSON.stringify(до.сегодня));
  проверить('комнат создано 3', до.сегодня.комнатСоздано === 3);
  проверить('партий начато 3', до.сегодня.партийНачато === 3);
  проверить('брошено 3, доиграно 0', до.сегодня.партийБрошено === 3 && до.сегодня.партийДоиграно === 0);
  проверить('людей 2 (Аня дважды — один человек)', до.сегодня.людей === 2);
  проверить('с ботами 2, с людьми 1', до.сегодня.партийСБотами === 2 && до.сегодня.партийСЛюдьми === 1);
  проверить('парами 1', до.сегодня.партийПарами === 1);
  проверить('по приглашению 1', до.сегодня.селиПоПриглашению === 1);
  проверить('в ответе нет номеров Telegram',
    JSON.stringify(до).indexOf('900001') === -1 && JSON.stringify(до).indexOf('люди') === -1);

  // Г. Автопрогон доигрывает партии по картам (без Telegram, без ботов).
  const выводПрогона = await запуститьИДождаться(
    [path.join(КОРЕНЬ, 'tests/сетевой-автопрогон.js'), String(ПОРТ)]);
  const строкаКомнат = (выводПрогона.match(/комнат за прогон: (\d+)/) || [])[1];
  console.log('  автопрогон: комнат ' + строкаКомнат);
  console.log('  ' + выводПрогона.split('\n').filter(function (с) { return /партий|сыгран|доигр/i.test(с); }).join('\n  '));

  const после = await спросить('/статистика');
  console.log('  после автопрогона: ' + JSON.stringify(после.сегодня));
  /* В каждой комнате прогон раздаёт дважды: партию доигрывает до конца,
     а реванш только начинает и оба выходят (tests/сетевой-автопрогон.js,
     строки 326–329). Значит на комнату — одна доигранная и одна брошенная. */
  const комнатПрогона = Number(строкаКомнат) || 0;
  const партийПрогона = 2 * комнатПрогона;
  проверить('комнат создано 3 + ' + комнатПрогона, после.сегодня.комнатСоздано === 3 + комнатПрогона);
  проверить('начато 3 + ' + партийПрогона, после.сегодня.партийНачато === 3 + партийПрогона);
  проверить('доиграно ' + комнатПрогона + ' (по одной на комнату)',
    после.сегодня.партийДоиграно === комнатПрогона);
  проверить('брошено 3 + ' + комнатПрогона + ' (брошенные реванши)',
    после.сегодня.партийБрошено === 3 + комнатПрогона);
  проверить('начато = доиграно + брошено (все партии учтены)',
    после.сегодня.партийНачато === после.сегодня.партийДоиграно + после.сегодня.партийБрошено);
  проверить('людей по-прежнему 2 (прогон без Telegram)', после.сегодня.людей === 2);
  проверить('с людьми 1 + ' + партийПрогона, после.сегодня.партийСЛюдьми === 1 + партийПрогона);
  проверить('сводка за 7 дней = сегодня', JSON.stringify(после.дней7) === JSON.stringify(после.сегодня));
  проверить('сводка за 30 дней = сегодня', JSON.stringify(после.дней30) === JSON.stringify(после.сегодня));
  проверить('день назван', после.день === статистика.ключДня());

  // Файл: записать и прочитать обратно другим процессом.
  статистика.дописать();
  const чтение = await запуститьИДождаться(['-e',
    'const с=require(' + JSON.stringify(path.join(КОРЕНЬ, 'server/статистика.js')) + ');' +
    'process.stdout.write(JSON.stringify(с.отчёт().сегодня))']);
  let прочитано = null;
  try { прочитано = JSON.parse(чтение); } catch (сбой) { прочитано = null; }
  console.log('  другой процесс прочитал: ' + чтение);
  проверить('файл прочитан обратно теми же числами',
    прочитано && JSON.stringify(прочитано) === JSON.stringify(после.сегодня));
}

сервер.запустить(ПОРТ, 2000);
пройти().then(function () {
  console.log(всёХорошо ? 'ИТОГ: всё сошлось.' : 'ИТОГ: есть беды, смотри выше.');
}).catch(function (сбой) {
  всёХорошо = false;
  console.log('Проверка сорвалась: ' + (сбой && сбой.stack || сбой));
}).then(function () {
  // Убираем за собой выдуманные числа и знакомства.
  статистика.забытьВсё();
  статистика.дописать();
  знакомые.забытьВсё();
  знакомые.дописать();
  process.exit(всёХорошо ? 0 : 1);
});
