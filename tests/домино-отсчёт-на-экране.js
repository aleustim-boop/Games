/* Партия втроём, доведённая просрочками до итога раунда (цель большая — партия не кончится). */
let часы = 5000000;
const настоящиеЧасы = Д.сейчас;
function довестиДоИтога() {
  Д.сейчас = () => часы;
  const п = Д.раздать(null, { игроки: ['и1', 'и2', 'и3'], цельДомино: 150 });
  for (let шаг = 0; шаг < 600 && п.игра.фаза === 'игра'; шаг++) { часы += 61000; Д.ходПоПросрочке(п); }
  return п;
}
const событиеВремени = { что: 'ход-по-времени', кто: 'и1', имя: 'Аня' };

