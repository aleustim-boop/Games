  const слова = ключ => Д.текстСобытия(событиеВремени, ключ);
  const свой = Д.видДляИгрока(п, 'и1', { событиеСырое: событиеВремени, событие: слова('и1') });
  assert.equal(свой.видСобытия, 'ход-по-времени');
  assert.equal(свой.событие, 'Время вышло — ход за вас сделал бот');
  const чужой = Д.видДляИгрока(п, 'и2', { событиеСырое: событиеВремени, событие: слова('и2') });
  assert.equal(чужой.событие, 'Аня: время вышло — ход сделал бот');
