проверка('число не прыгает вверх на новом ответе сервера (сервер округляет вверх, ответы раз в 0,7 с)', () => {
  // Настоящий остаток идёт вниз с 50,3 с; сервер каждый ответ присылает его округлённым вверх.
  let ответ = null, прежнее = Infinity;
  for (let мс = 0; мс <= 20000; мс += 100) {
    if (!ответ || мс - ответ.получено >= 700) ответ = { остаток: Math.ceil(50.3 - мс / 1000), получено: мс };
    const видно = Э.секундыСейчас(ответ.остаток, ответ.получено, мс);
    assert.ok(видно <= прежнее, 'число прыгнуло вверх: было ' + прежнее + ', стало ' + видно + ' на ' + мс + ' мс');
    const настоящий = Math.ceil(50.3 - мс / 1000);   // ответ сервера теряет дробь, поэтому экран может быть выше на единицу, но не ниже
    assert.ok(видно >= настоящий && видно <= настоящий + 1, 'на ' + мс + ' мс экран ' + видно + ', настоящий остаток ' + настоящий);
    прежнее = видно;
  }
});

