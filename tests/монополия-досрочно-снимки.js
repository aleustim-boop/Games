function ломатьОдной(порча, счёт, сеть) {
  console.log('=== Ломающий прогон: ' + порча.заголовок + ' — обязана покраснеть на ' + порча.метка + ' ===');
  счёт.всего++;
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'монополия-досрочно-лом-'));
  try {
    const имяФайла = порча.файл || ИМЯ_ЭКРАНА;
    const текст = fs.readFileSync(path.join(ПРОЕКТ, имяФайла), 'utf8');
    const вхождений = текст.split(порча.было).length - 1;
    if (вхождений !== 1) {
      console.log('ПРОВАЛ: образец порчи найден в ' + имяФайла + ' ' + вхождений + ' раз (нужно ровно 1): ' + порча.было);
      счёт.плохо++;
      return;
    }
    const копия = path.join(папка, path.basename(имяФайла));
    fs.writeFileSync(копия, текст.replace(порча.было, () => порча.стало), 'utf8');
    console.log('Порченая копия: ' + копия);
    const доводы = [__filename, имяФайла === ИМЯ_СЦЕНЫ ? '--css' : '--экран', копия, '--снимки', path.join(папка, 'снимки')];
    if (сеть) доводы.push('--сеть', сеть);
    // Дочерний прогон иногда зависает (браузер встал): убитый по времени (код null) — не ответ проверки, а помеха;
    // даём ему до трёх попыток с коротким сроком, чтобы честная порча не краснела «через раз» из-за зависшего браузера.
    let прогон = null;
    for (let попытка = 1; попытка <= 3; попытка++) {
      прогон = spawnSync(process.execPath, доводы, { encoding: 'utf8', timeout: 240000 });
      if (прогон.status !== null) break;
      console.log('  дочерний прогон завис и убит по времени (попытка ' + попытка + ' из 3) — запускаю заново');
    }
    const плохие = (прогон.stdout || '').split('\n').filter(с => с.includes('ПЛОХО'));
    const наМетке = плохие.filter(с => с.includes(порча.метка));
    console.log(наМетке.slice(0, 3).join('\n') + (прогон.stderr ? '\nstderr: ' + прогон.stderr.slice(0, 300) : ''));
    const ок = прогон.status === 1 && наМетке.length > 0;
    console.log(ок ? 'ПОКРАСНЕЛ на ' + порча.метка + ' (красных строк метки: ' + наМетке.length + ', всего красных: ' + плохие.length + ')'
      : 'ПРОВАЛ: не покраснел на ' + порча.метка + ' (код ' + прогон.status + ')');
    if (!ок) счёт.плохо++;
  } finally {
    fs.rmSync(папка, { recursive: true, force: true });
  }
}

function довод(имя) { const г = process.argv.indexOf(имя); return г !== -1 && process.argv[г + 1] ? path.resolve(process.argv[г + 1]) : null; }

