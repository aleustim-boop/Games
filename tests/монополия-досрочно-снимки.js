/** Настоящее нажатие мышью по кнопке с точной подписью внутри селектора. */
async function нажать(страница, корень, подпись) {
  const к = страница.locator(корень + ' button').filter({ hasText: new RegExp('^\\s*' + подпись + '\\s*$') });
  const сколько = await к.count();
  if (сколько !== 1) return 'кнопка «' + подпись + '» в ' + корень + ': найдено ' + сколько + ' (нужна одна)';
  try { await к.first().click({ timeout: 4000 }); } catch (е) { return 'нажатие «' + подпись + '» не вышло: ' + String(е.message).split('\n')[0]; }
  await страница.waitForTimeout(400);
  return '';
}
async function нажатьУзел(страница, селектор) {
  const к = страница.locator(селектор);
  if (await к.count() !== 1) return 'узел ' + селектор + ': найдено ' + await к.count();
  try { await к.first().click({ timeout: 4000 }); } catch (е) { return 'нажатие ' + селектор + ' не вышло: ' + String(е.message).split('\n')[0]; }
  await страница.waitForTimeout(400);
  return '';
}

