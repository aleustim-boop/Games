/** Раскладка низа окна итога: все кнопки внутри «.mono-итог-кнопки» — рамки, ширина полосы кнопок, «В друзья» отдельно. */
function замерРаскладкиКнопок() {
  const полоса = document.querySelector('#mono-modal-body .mono-итог-кнопки');
  if (!полоса) return { есть: false };
  const п = полоса.getBoundingClientRect();
  const кнопки = Array.from(полоса.querySelectorAll('button')).filter(function (б) {
    const р = б.getBoundingClientRect(), с = getComputedStyle(б);
    return с.display !== 'none' && р.width > 0 && р.height > 0;
  }).map(function (б) {
    const р = б.getBoundingClientRect();
    return { текст: б.textContent.trim(), x: р.left, y: р.top, r: р.right, b: р.bottom, w: р.width, h: р.height };
  });
  return { есть: true, лево: п.left, право: п.right, ширина: п.width, кнопки: кнопки };
}

/** Чистая проверка раскладки «В друзья» (без страницы: годится и для разбора вручную). Возвращает список бед. */
function бедыРаскладкиДрузей(з) {
  const беды = [];
  if (!з.есть) return ['полоса кнопок «.mono-итог-кнопки» не найдена'];
  const друзья = з.кнопки.filter(function (б) { return /^В друзья/.test(б.текст); });
  if (друзья.length !== 2) return ['кнопок «В друзья» найдено ' + друзья.length + ' (нужно 2)'];
  // Не уже разумной доли полосы: узкие кнопки слева и дыра справа — как на забракованном снимке.
  друзья.forEach(function (б) {
    if (б.w < з.ширина * 0.4) беды.push('«' + б.текст + '» узкая: ' + Math.round(б.w) + ' из ' + Math.round(з.ширина));
    if (б.h < МИН_ВЫСОТА_КНОПКИ - 0.5) беды.push('«' + б.текст + '» ниже ' + МИН_ВЫСОТА_КНОПКИ + ': ' + Math.round(б.h));
  });
  // Правый край ряда доходит до правого края содержимого окна: дыры справа нет.
  const правыйКрай = Math.max.apply(null, друзья.map(function (б) { return б.r; }));
  if (правыйКрай < з.право - 2) беды.push('справа дыра: край кнопок ' + Math.round(правыйКрай) + ', край полосы ' + Math.round(з.право));
  // Кнопки не пересекаются ни друг с другом, ни с главными и между ними есть зазор (не слиплись).
  for (let i = 0; i < з.кнопки.length; i++) {
    for (let j = i + 1; j < з.кнопки.length; j++) {
      const а = з.кнопки[i], б = з.кнопки[j];
      const поГоризонтали = Math.min(а.r, б.r) - Math.max(а.x, б.x);
      const поВертикали = Math.min(а.b, б.b) - Math.max(а.y, б.y);
      if (поГоризонтали > 0.5 && поВертикали > 0.5) беды.push('«' + а.текст + '» пересекается с «' + б.текст + '»');
      else if (поГоризонтали > 0.5 && поВертикали > -3) беды.push('«' + а.текст + '» и «' + б.текст + '» слиплись по вертикали');
      else if (поВертикали > 0.5 && поГоризонтали > -3) беды.push('«' + а.текст + '» и «' + б.текст + '» слиплись по горизонтали');
    }
  }
  return беды;
}

