/* =====================================================================
   ОТКРЫВАЕТСЯ ЛИ ЛЕНТА «ЧТО БЫЛО» НАСТОЯЩИМ НАЖАТИЕМ.

   ЭТО НЕ АВТОПРОГОН ДЛЯ NODE. Файл вставляется в консоль браузера, когда
   игра уже открыта и партия идёт (http://127.0.0.1:8123/index.html).

   ЗАЧЕМ. Единственная дверь в ленту — строка подсказки внизу экрана.
   Нажатие по ней проходит по странице снизу вверх: сперва его получает
   сама строка, потом — всё, внутри чего она лежит. Если по дороге наверх
   кто-то ещё решит, что «раз лента открыта — закрою её», то плашка
   откроется и в тот же миг закроется, а человек не увидит ничего.

   Такую поломку не поймать ни глазами по коду (каждый кусок по отдельности
   правильный), ни роботом, который зовёт функции напрямую: он открывает
   ленту в обход самого нажатия. Ловится она только настоящим нажатием
   и взглядом на то, что было СРАЗУ ПОСЛЕ обработчика строки.

   КАК ПРОВЕРЯЕТ. К строке подсказки приставляется наблюдатель, который
   срабатывает после её собственного обработчика. Дальше делается обычное
   нажатие, и сравниваются два мига:
       «сразу после обработчика строки» и «когда нажатие дошло доверху».
   Открылась и осталась — хорошо. Открылась и пропала — вот она, поломка.

   Заодно проверяется, где по высоте строки лента открывается, а где —
   нет: у самого низа строки нажатие нарочно считается промахом мимо
   карты, и лента открываться не должна.

   ЧТО ЗАПУСКАТЬ (звать по одному):
       Лента.тап()        — одно нажатие в середину строки, подробный ответ
       Лента.поВысоте()   — построчно сверху вниз: где открывается, где нет
       Лента.всё()
   ===================================================================== */

(function () {
  'use strict';

  function эл(id) { return document.getElementById(id); }

  /** Видна ли плашка «Что было» человеку прямо сейчас. */
  function плашкаВидна() {
    const п = эл('экран-ленты');
    return Boolean(п && п.classList.contains('экран--виден'));
  }

  /** Что сейчас написано в строке подсказки. */
  function подсказка() {
    const у = эл('подсказка-текст') || эл('подсказка');
    return у ? (у.textContent || '').trim() : '';
  }

  /* Наблюдатель: срабатывает на том же нажатии, но ПОСЛЕ обработчика самой
     строки. Обработчики зовут в том порядке, в каком их повесили, а наш
     вешается последним — значит, он видит плашку такой, какой её оставила
     строка подсказки. */
  let мигПослеСтроки = null;
  (function приставитьНаблюдателя() {
    const строка = эл('подсказка');
    if (!строка) return;
    строка.addEventListener('click', function () { мигПослеСтроки = плашкаВидна(); });
  })();

  /**
   * Одно настоящее нажатие по точке экрана.
   *
   * Кому оно достанется, спрашиваем у самого браузера («что лежит под этой
   * точкой») — так же, как он решает это при касании пальцем. Поэтому
   * нажатие, попавшее в то, что лежит сверху, до нижнего и не дойдёт:
   * ровно как у живого человека.
   */
  function нажать(x, y) {
    const узел = document.elementFromPoint(x, y);
    if (!узел) return null;
    узел.dispatchEvent(new MouseEvent('click', {
      bubbles: true, cancelable: true, composed: true,
      clientX: x, clientY: y, view: window
    }));
    return узел;
  }

  /** Закрыть плашку, если она открыта, — чтобы каждая проверка начиналась чисто. */
  function прибраться() {
    if (плашкаВидна()) {
      const назад = эл('кнопка-лента-назад');
      if (назад) назад.click();
    }
  }

  /* ------------------------------------------------------------------ */

  function тап() {
    прибраться();
    const строка = эл('подсказка');
    if (!строка) return { беда: 'на странице нет строки подсказки' };
    const рамка = строка.getBoundingClientRect();
    const x = Math.round((рамка.left + рамка.right) / 2);
    const y = Math.round((рамка.top + рамка.bottom) / 2);

    мигПослеСтроки = null;
    const кому = нажать(x, y);
    const итог = {
      куда: 'середина строки подсказки, точка ' + x + ',' + y,
      нажатиеДосталось: кому ? (кому.id || кому.className || кому.tagName) : 'никому',
      сразуПослеСтроки: мигПослеСтроки,
      когдаНажатиеДошлоДоверху: плашкаВидна(),
      вСтрокеБыло: подсказка()
    };
    if (мигПослеСтроки === true && итог.когдаНажатиеДошлоДоверху === false) {
      итог.ПОЛОМКА = 'плашка открылась и тут же закрылась на том же нажатии — ' +
                     'человек ленту не увидит вовсе';
    } else if (мигПослеСтроки !== true) {
      итог.ПОЛОМКА = 'строка подсказки на нажатие ленту не открыла вовсе';
    } else {
      итог.всёХорошо = 'лента открылась и осталась открытой';
    }
    console.log(итог);
    прибраться();
    return итог;
  }

  /**
   * Построчно сверху вниз по строке подсказки: где лента открывается,
   * а где нажатие считается промахом мимо карты.
   */
  function поВысоте() {
    прибраться();
    const строка = эл('подсказка');
    if (!строка) return { беда: 'на странице нет строки подсказки' };
    const рамка = строка.getBoundingClientRect();
    const x = Math.round((рамка.left + рамка.right) / 2);
    const ряды = [];
    for (let y = Math.ceil(рамка.top); y <= Math.floor(рамка.bottom) - 1; y++) {
      прибраться();
      мигПослеСтроки = null;
      нажать(x, y);
      ряды.push({ y: y, открылась: мигПослеСтроки === true, осталась: плашкаВидна() });
    }
    прибраться();

    const открылась = ряды.filter((р) => р.открылась).length;
    const осталась = ряды.filter((р) => р.осталась).length;
    const итог = {
      строкаПодсказки: 'от ' + Math.round(рамка.top) + ' до ' + Math.round(рамка.bottom) +
                       ' (' + Math.round(рамка.height) + ' точек)',
      точекПроверено: ряды.length,
      открылаЛенту: открылась,
      лентаОсталасьОткрытой: осталась
    };
    if (открылась > 0 && осталась === 0) {
      итог.ПОЛОМКА = 'ни одна точка строки не оставила ленту открытой: ' +
                     'плашка открывается и тут же закрывается';
    }
    if (открылась === 0) итог.ПОЛОМКА = 'ни одна точка строки ленту не открыла';
    console.log(итог);
    console.table(ряды);
    return итог;
  }

  window.Лента = {
    тап: тап,
    поВысоте: поВысоте,
    всё: function () { const а = тап(); const б = поВысоте(); return { тап: а, поВысоте: б }; }
  };
  console.log('Проверка ленты готова. Зовите: Лента.тап(), Лента.поВысоте(), Лента.всё().');
})();
