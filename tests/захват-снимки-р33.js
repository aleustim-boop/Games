/* Подбор посева: в итоге раунда 1 человек берёт область (Раскрытие пишет «Вы взяли …»). Считается теми же правилами, что и на экране. */
function подобратьПосев(мест) {
  const П = window.ЗахватПравила, Б = window.ЗахватБот, Р = window.ЗахватРаскрытие;
  const ген = с0 => { let с = с0 >>> 0; return () => { с = (с + 0x6D2B79F5) | 0; let т = Math.imul(с ^ (с >>> 15), 1 | с); т = (т + Math.imul(т ^ (т >>> 7), 61 | т)) ^ т; return ((т ^ (т >>> 14)) >>> 0) / 4294967296; }; };
  window.__ген = ген;
  const К = window.ЗахватКарты;
  for (let с0 = 1; с0 <= 800; с0++) {
    try {
      const игроки = ['человек']; for (let н = 1; н < мест; н++) игроки.push('бот-' + н);
      const проба = П.новаяПартия({ игроки: игроки, люди: ['человек'], сейчас: Date.now() }, ген(с0));
      const соседи = К.соседство(П.картаПартии(проба));
      const мои = []; for (let н = 1; н < проба.хозяева.length; н++) if (проба.хозяева[н] === 'человек') мои.push(н);
      for (const из of мои) {
        for (const в of (соседи[из] || [])) {
          if (проба.хозяева[в] === 'человек') continue;
          const р = ген(с0);
          const до = П.новаяПартия({ игроки: игроки, люди: ['человек'], сейчас: Date.now() }, р);
          const п = до.подкрепление.человек;
          const сколько = до.войска[из] + п - 1;
          if (сколько < 1) continue;
          const ч = { расстановка: { [из]: п }, приказы: [{ из: из, в: в, сколько: сколько }] };
          const чер = {};
          до.игроки.forEach(к => { if (!П.вИгре(до, к)) return; чер[к] = П.остатокПоПросрочке(до, к, к === 'человек' ? ч : Б.решить(до, к, 'сложный', р)); });
          const хозДо = до.хозяева.slice();
          const разбор = П.разобратьРаунд(JSON.parse(JSON.stringify(до)), чер, р);
          const р2 = Р.построить({ события: разбор.события, раунд: разбор.раунд, карта: П.картаПартии(разбор.партия).ключ, имена: {}, я: 'человек', хозяеваДо: хозДо, хозяеваПосле: разбор.партия.хозяева, всегоРаундов: разбор.партия.всегоРаундов, плотно: true });
          if ((р2.итог || []).some(т => /^Вы взяли /.test(т))) return { с0: с0, из: из, в: в, п: п, карта: П.картаПартии(до).ключ, строки: р2.итог.slice() };
        }
      }
    } catch (е) { /* следующий посев */ }
  }
  return null;
}

