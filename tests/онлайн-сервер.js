'use strict';

/* Проверка серверной части «Онлайн» (штаб/план-онлайн-дашборд.md, этап 2):
   пульс POST /пульс и закрытая дверь GET /штаб-онлайн.

   Как устроено. Сервер поднимается ОТДЕЛЬНЫМ процессом на порту 8799
   (боевой 8790 не трогаем) через маленькую запускалку во временной папке:
   она ставит выдуманный токен оснасткаДляПроверки — настоящий токен
   проверке не нужен и не читается — и зовёт запустить(). Отдельный процесс
   нужен, чтобы собрать его журнал (вывод) и убедиться, что номеров там нет.
   Папка данных (ДАННЫЕ_ИГРЫ) — тоже во временной папке: там сервер создаёт
   ключ штаба, и проверка читает его оттуда.

   Запуск:
     node tests/онлайн-сервер.js                   обычный прогон, всё зелёное
     node tests/онлайн-сервер.js --сломать         копия сервера без проверки
                                                   ключа — обязана покраснеть
     node tests/онлайн-сервер.js --сломать=туннель копия без проверки заголовков
                                                   туннеля — обязана покраснеть
   Ломается КОПИЯ сервер.js во временной папке, настоящий файл не трогается. */

const path = require('path');
const os = require('os');
const fs = require('fs');
const crypto = require('crypto');
const { spawn } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const ПАПКА_СЕРВЕРА = path.join(КОРЕНЬ, 'server');
const ФАЙЛ_СЕРВЕРА = path.join(ПАПКА_СЕРВЕРА, 'сервер.js');
const ПОРТ = 8799;
const АДРЕС = 'http://127.0.0.1:' + ПОРТ;
const ВЫДУМАННЫЙ_ТОКЕН = '123456:проверка-онлайна-не-настоящий-токен';
const ЗАГОЛОВОК_КЛЮЧА = 'x-klyuch-shtaba';

const НОМЕР_ПОДПИСАННЫЙ = 777000111;
const НОМЕР_БЕЗ_ПОДПИСИ = 777000222;

/* Какая поломка: нет — обычный прогон. */
const доводСломать = process.argv.slice(2).find(function (д) { return /^--сломать/.test(д); });
const ПОЛОМКА = !доводСломать ? null : (доводСломать === '--сломать=туннель' ? 'туннель' : 'ключ');

const ВРЕМЕННАЯ = fs.mkdtempSync(path.join(os.tmpdir(), 'онлайн-сервер-'));
const ПАПКА_ДАННЫХ = path.join(ВРЕМЕННАЯ, 'данные');
process.on('exit', function () {
  try { fs.rmSync(ВРЕМЕННАЯ, { recursive: true, force: true }); } catch (сбой) { /* не страшно */ }
});

let проверок = 0;
let провалов = 0;
function проверить(что, правда) {
  проверок++;
  if (!правда) провалов++;
  console.log((правда ? '  ок   ' : '  БЕДА ') + что);
}

/* Подпись initData тем же способом, что в tests/проверка-статистики.js,
   только выдуманным токеном — его же сервер получил через оснастку. */
function подписать(кто) {
  const поля = new URLSearchParams();
  поля.set('user', JSON.stringify(кто));
  поля.set('auth_date', String(Math.floor(Date.now() / 1000)));
  const строки = [];
  for (const пара of поля) строки.push(пара[0] + '=' + пара[1]);
  строки.sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(ВЫДУМАННЫЙ_ТОКЕН).digest();
  поля.set('hash', crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex'));
  return поля.toString();
}

/**
 * Копия сервер.js во временной папке с вырезанной проверкой.
 * Пути require('./…') переписываются на полные — копия живёт не в server/.
 * Вырезаемая строка обязана найтись: не нашлась — это провал, а не пропуск.
 */
function сделатьСломаннуюКопию(поломка) {
  let текст = fs.readFileSync(ФАЙЛ_СЕРВЕРА, 'utf8');
  текст = текст.replace(/require\('\.\/([^']+)'\)/g, function (всё, имя) {
    return 'require(' + JSON.stringify(path.join(ПАПКА_СЕРВЕРА, имя)) + ')';
  });
  const вырезать = поломка === 'ключ'
    ? /\n\s*if \(!ключШтабаВерный\([^\n]*\n/
    : /\n\s*if \(пришёлСнаружи\(запрос\)\)[^\n]*\n/;
  if (!вырезать.test(текст)) {
    console.log('  БЕДА ломать нечего: строка проверки «' + поломка + '» в сервер.js не найдена');
    process.exit(1);
  }
  текст = текст.replace(вырезать, '\n');
  const копия = path.join(ВРЕМЕННАЯ, 'сервер-сломанный.js');
  fs.writeFileSync(копия, текст, 'utf8');
  return копия;
}

/* Ключ штаба проверка придумывает сама: проверочный сервер ключей не
   создаёт (это право только настоящего сервера с диском), а лишь читает
   готовый файл из своей папки данных. Кладёт файл запускалка. */
const КЛЮЧ = crypto.randomBytes(32).toString('hex');

/* Запускалка: выдуманный токен и поддельная труба (в Telegram не ходим),
   файл ключа во временной папке данных — до запуска сервера. */
function сделатьЗапускалку() {
  const файл = path.join(ВРЕМЕННАЯ, 'запускалка.js');
  const текст =
    "'use strict';\n" +
    "const fs = require('fs');\n" +
    "const path = require('path');\n" +
    'fs.mkdirSync(process.env.ДАННЫЕ_ИГРЫ, { recursive: true });\n' +
    "fs.writeFileSync(path.join(process.env.ДАННЫЕ_ИГРЫ, 'ключ-штаба'), process.argv[4] + '\\n', 'utf8');\n" +
    'const сервер = require(process.argv[2]);\n' +
    'сервер.оснасткаДляПроверки(' + JSON.stringify(ВЫДУМАННЫЙ_ТОКЕН) +
    ', function () { return { ok: false }; });\n' +
    'сервер.запустить(Number(process.argv[3]), 2000);\n';
  fs.writeFileSync(файл, текст, 'utf8');
  return файл;
}

const спать = function (мс) { return new Promise(function (f) { setTimeout(f, мс); }); };

async function живОтвечает() {
  try {
    const о = await fetch(АДРЕС + '/здоровье');
    return о.ok;
  } catch (сбой) {
    return false;
  }
}

function послать(путь, тело) {
  return fetch(АДРЕС + путь, {
    method: 'POST', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(тело || {})
  });
}

function спроситьСводку(заголовки) {
  return fetch(АДРЕС + '/штаб-онлайн', { headers: заголовки || {} });
}

async function пройти(журнал) {
  const ключ = КЛЮЧ;

  // Подписанный пульс учитывается.
  const пульс = await послать('/пульс', { initData: подписать({ id: НОМЕР_ПОДПИСАННЫЙ, first_name: 'Проверкин' }), игра: 'шашки' });
  const текстПульса = await пульс.text();
  проверить('подписанный пульс: 200 {ок:true}', пульс.status === 200 && JSON.parse(текстПульса).ок === true);
  проверить('в ответе на пульс нет номера', текстПульса.indexOf(String(НОМЕР_ПОДПИСАННЫЙ)) === -1);

  // Пульс без настоящей подписи: номер в поддельном initData и в теле.
  const поддельный = new URLSearchParams();
  поддельный.set('user', JSON.stringify({ id: НОМЕР_БЕЗ_ПОДПИСИ, first_name: 'Самозванец' }));
  поддельный.set('auth_date', String(Math.floor(Date.now() / 1000)));
  поддельный.set('hash', '0'.repeat(64));
  const безПодписи = await послать('/пульс', { initData: поддельный.toString(), игра: 'дурак', номер: НОМЕР_БЕЗ_ПОДПИСИ });
  const ответБезПодписи = await безПодписи.json();
  проверить('пульс без подписи: ок:false', ответБезПодписи.ок === false);

  // GET на /пульс — не принимается.
  const getПульс = await fetch(АДРЕС + '/пульс');
  проверить('GET /пульс не отвечает 200 (ответ ' + getПульс.status + ')', getПульс.status !== 200);

  // Сводка с верным ключом.
  const сводка = await спроситьСводку({ [ЗАГОЛОВОК_КЛЮЧА]: ключ });
  const текстСводки = await сводка.text();
  let данные = null;
  try { данные = JSON.parse(текстСводки); } catch (сбой) { данные = null; }
  проверить('сводка с ключом: 200', сводка.status === 200);
  const сейчас = данные && Array.isArray(данные.сейчас) ? данные.сейчас : [];
  const запись = сейчас.find(function (з) { return з.номер === String(НОМЕР_ПОДПИСАННЫЙ); });
  проверить('подписанный пульс виден в «сейчас» с игрой «шашки» и именем',
    Boolean(запись) && запись.игра === 'шашки' && запись.имя === 'Проверкин');
  проверить('пульс без подписи не учтён', текстСводки.indexOf(String(НОМЕР_БЕЗ_ПОДПИСИ)) === -1);

  // Отказы.
  const безКлюча = await спроситьСводку({});
  проверить('без ключа: 403 (ответ ' + безКлюча.status + ')', безКлюча.status === 403);
  const чужойКлюч = (ключ[0] === 'a' ? 'b' : 'a') + ключ.slice(1);
  const неверный = await спроситьСводку({ [ЗАГОЛОВОК_КЛЮЧА]: чужойКлюч });
  проверить('неверный ключ той же длины: 403 (ответ ' + неверный.status + ')', неверный.status === 403);
  const короткий = await спроситьСводку({ [ЗАГОЛОВОК_КЛЮЧА]: ключ.slice(0, 10) });
  проверить('ключ другой длины: 403 (ответ ' + короткий.status + ')', короткий.status === 403);
  for (const имя of ['cf-connecting-ip', 'cf-ray', 'x-forwarded-for', 'x-real-ip']) {
    const снаружи = await спроситьСводку({ [ЗАГОЛОВОК_КЛЮЧА]: ключ, [имя]: '203.0.113.5' });
    const тело = await снаружи.text();
    проверить('ключ + ' + имя + ': 403 (ответ ' + снаружи.status + ')',
      снаружи.status === 403 && тело.indexOf(String(НОМЕР_ПОДПИСАННЫЙ)) === -1);
  }

  // Журнал: сервер в нём что-то сказал (иначе проверка пустая), номеров нет.
  проверить('журнал сервера собран (строка о запуске есть)', журнал().indexOf('8799') !== -1);
  проверить('в журнале сервера нет номеров',
    журнал().indexOf(String(НОМЕР_ПОДПИСАННЫЙ)) === -1 && журнал().indexOf(String(НОМЕР_БЕЗ_ПОДПИСИ)) === -1);
}

async function главное() {
  if (await живОтвечает()) {
    console.log('  БЕДА порт ' + ПОРТ + ' уже занят чужой копией — проверка не пойдёт');
    process.exit(1);
  }

  const какойСервер = ПОЛОМКА ? сделатьСломаннуюКопию(ПОЛОМКА) : ФАЙЛ_СЕРВЕРА;
  if (ПОЛОМКА) console.log('Ломающий прогон: копия сервера без проверки «' + ПОЛОМКА + '» — ждём провала.');

  const дитя = spawn(process.execPath, [сделатьЗапускалку(), какойСервер, String(ПОРТ), КЛЮЧ], {
    env: Object.assign({}, process.env, { ДАННЫЕ_ИГРЫ: ПАПКА_ДАННЫХ, GAMES_DATA: ПАПКА_ДАННЫХ })
  });
  let журнал = '';
  дитя.stdout.on('data', function (к) { журнал += к; });
  дитя.stderr.on('data', function (к) { журнал += к; });
  let вышел = false;
  дитя.on('exit', function () { вышел = true; });

  let поднялся = false;
  try {
    for (let i = 0; i < 50 && !вышел; i++) {
      if (await живОтвечает()) { поднялся = true; break; }
      await спать(100);
    }
    проверить('свой сервер поднялся на ' + ПОРТ + ' (PID ' + дитя.pid + ')', поднялся && !вышел);
    if (поднялся && !вышел) await пройти(function () { return журнал; });
  } catch (сбой) {
    проверить('проверка не сорвалась: ' + (сбой && сбой.message), false);
  } finally {
    /* Гасим только свой процесс и ждём его выхода. process.exit() здесь
       не зовём: на Windows он роняет node, пока у fetch открыты соединения;
       код выхода ставим, а процесс кончается сам. */
    if (!вышел) {
      const ушёл = new Promise(function (f) { дитя.once('exit', f); });
      дитя.kill();
      await ушёл;
    }
  }

  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
  process.exitCode = провалов === 0 ? 0 : 1;

  /* Ломающий прогон засчитывается, только если сломанная копия ПОДНЯЛАСЬ
     и покраснела на самих проверках двери. Не поднялась — краснота ничего
     не доказывает (копия могла упасть на опечатке), прогон недействителен. */
  if (ПОЛОМКА && !поднялся) {
    console.log('ЛОМАЮЩИЙ ПРОГОН НЕДЕЙСТВИТЕЛЕН: сломанная копия не поднялась — покраснение не засчитывается.');
    process.exitCode = 3;
  }
}

главное();
