/*
  Медленный посредник — инструмент тестировщика.

  Зачем он нужен. Дома сервер отвечает почти мгновенно (за сотые доли секунды),
  и поэтому дома невозможно увидеть, как игра ведёт себя у человека с обычным
  мобильным интернетом, где ответ идёт полсекунды-две. А именно там вылезают
  ошибки вида «нажал кнопку, пока игра ещё думала».

  Что он делает. Слушает свой порт, пересылает всё на настоящий сервер комнат
  и задерживает ответ на заданное время. Игру запускаем через него:
      index.html?сервер=http://127.0.0.1:8791

  Запуск:
      node tests/медленный-посредник.js [порт] [задержка_мс] [адрес_сервера]
  Пример:
      node tests/медленный-посредник.js 8791 1500 http://127.0.0.1:8790
*/

const http = require('http');

const порт = Number(process.argv[2] || 8791);
const задержка = Number(process.argv[3] || 1500);
const адресНастоящего = process.argv[4] || 'http://127.0.0.1:8790';
const разбор = new URL(адресНастоящего);

const сервер = http.createServer((запрос, ответНаружу) => {
  // Собираем тело запроса целиком
  const куски = [];
  запрос.on('data', (к) => куски.push(к));
  запрос.on('end', () => {
    const тело = Buffer.concat(куски);
    const заголовки = Object.assign({}, запрос.headers);
    заголовки.host = разбор.host;

    const внутрь = http.request({
      hostname: разбор.hostname,
      port: разбор.port || 80,
      path: запрос.url,
      method: запрос.method,
      headers: заголовки
    }, (ответВнутри) => {
      const части = [];
      ответВнутри.on('data', (ч) => части.push(ч));
      ответВнутри.on('end', () => {
        // Вот она, «медленная связь»: держим ответ у себя лишнее время
        setTimeout(() => {
          ответНаружу.writeHead(ответВнутри.statusCode, ответВнутри.headers);
          ответНаружу.end(Buffer.concat(части));
        }, задержка);
      });
    });

    внутрь.on('error', (сбой) => {
      ответНаружу.writeHead(502, { 'Content-Type': 'application/json; charset=utf-8' });
      ответНаружу.end(JSON.stringify({ ошибка: 'посредник не достучался до сервера: ' + сбой.message }));
    });

    внутрь.setTimeout(120000);
    внутрь.end(тело);
  });
});

сервер.listen(порт, '127.0.0.1', () => {
  console.log('Медленный посредник слушает порт ' + порт +
    ', задержка ' + задержка + ' мс, настоящий сервер ' + адресНастоящего);
  console.log('Открывайте игру так: http://127.0.0.1:8130/index.html?сервер=http://127.0.0.1:' + порт);
});
