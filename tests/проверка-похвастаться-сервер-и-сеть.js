'use strict';

/* Проверка «Похвастаться победой».
   1. Сервер: слова победы — буква в букву с правилом из js/game.js;
      описание проверяется поле за полем; чужая ссылка не проходит.
   2. Сеть: Сеть.похвастаться в имитации страницы — три дороги
      (поверх, список чатов, буфер) и что уходит серверу. Сервер здесь
      подменён: настоящий Telegram для выдуманного игрока не ответит. */

const fs = require('fs');
const vm = require('vm');
const path = require('path');
const КОРЕНЬ = require('path').resolve(__dirname, '..');   // корень проекта — от этого файла, а не зашитый
const сервер = require(path.join(КОРЕНЬ, 'server/сервер.js'));

let всёХорошо = true;
function проверить(что, правда) {
  console.log((правда ? '  ок   ' : '  БЕДА ') + что);
  if (!правда) всёХорошо = false;
}

console.log('1. Сервер: слова и проверка описания');
const слова = function (о) {
  const описание = сервер.описаниеПобеды(Object.assign({ игра: 'дурак', исход: 'победа' }, о));
  return описание ? сервер.словаПобеды(описание) : null;
};
проверить('сложный бот вшестером', слова({ соперники: 'боты', уровень: 'сложный', игроков: 6 }) ===
  'Победа в подкидном дураке над сложным ботом вшестером. Сыграем?');
проверить('обычный бот вдвоём — без слова про стол', слова({ соперники: 'боты', уровень: 'обычный', игроков: 2 }) ===
  'Победа в подкидном дураке над обычным ботом. Сыграем?');
проверить('лёгкий бот парами', слова({ соперники: 'боты', уровень: 'лёгкий', игроков: 4, парами: true }) ===
  'Победа в подкидном дураке над лёгким ботом парами. Сыграем?');
проверить('уровень пустой — «обычным»', слова({ соперники: 'боты', уровень: '', игроков: 3 }) ===
  'Победа в подкидном дураке над обычным ботом втроём. Сыграем?');
проверить('люди вчетвером', слова({ соперники: 'люди', игроков: 4 }) ===
  'Победа в подкидном дураке вчетвером с друзьями. Сыграем?');
проверить('люди вдвоём — «с другом»', слова({ соперники: 'люди', игроков: 2 }) ===
  'Победа в подкидном дураке с другом. Сыграем?');
проверить('люди парами', слова({ соперники: 'люди', игроков: 4, парами: true }) ===
  'Победа в подкидном дураке парами с друзьями. Сыграем?');
проверить('поражение — не описание победы', сервер.описаниеПобеды({ игра: 'дурак', исход: 'поражение', соперники: 'боты', игроков: 2 }) === null);
проверить('чужая игра — отказ', сервер.описаниеПобеды({ игра: 'шашки', исход: 'победа', соперники: 'боты', игроков: 2 }) === null);
проверить('семеро — отказ', сервер.описаниеПобеды({ игра: 'дурак', исход: 'победа', соперники: 'боты', игроков: 7 }) === null);
проверить('выдуманный уровень превращается в пустой',
  сервер.описаниеПобеды({ игра: 'дурак', исход: 'победа', соперники: 'боты', уровень: '<b>x</b>', игроков: 2 }).уровень === '');
проверить('ссылка на игру без кода — наша', сервер.этоНашаСсылкаНаИгру('https://t.me/BoardGamesBot/BoardGames'));
проверить('ссылка с кодом — не для победы', !сервер.этоНашаСсылкаНаИгру('https://t.me/BoardGamesBot/BoardGames?startapp=ABCD'));
проверить('чужой сайт — нет', !сервер.этоНашаСсылкаНаИгру('https://example.com/BoardGames'));
проверить('t.me/share — нет', !сервер.этоНашаСсылкаНаИгру('https://t.me/share/url?url=x'));

console.log('2. Сеть.похвастаться в имитации страницы');
const описание = {
  игра: 'дурак', исход: 'победа', соперники: 'боты', уровень: 'сложный', игроков: 6,
  парами: false, переводной: false, серия: 3,
  слова: 'Победа в подкидном дураке над сложным ботом вшестером. Сыграем?'
};

function собратьОкно(настройки) {
  const тела = [];
  const буфер = { текст: null };
  const открытые = [];
  const показанные = [];
  const приложение = {
    initData: 'user=%7B%22id%22%3A1%7D&hash=abc',
    platform: настройки.платформа || 'android',
    isVersionAtLeast: function () { return true; },
    openTelegramLink: function (адрес) { открытые.push(адрес); }
  };
  if (настройки.поверх) {
    приложение.shareMessage = function (номер, готово) {
      показанные.push(номер);
      готово(настройки.отправит === true);
    };
  }
  const память = new Map();
  const памятьБраузера = {
    getItem: function (к) { return память.has(к) ? память.get(к) : null; },
    setItem: function (к, ч) { память.set(к, String(ч)); },
    removeItem: function (к) { память.delete(к); }
  };
  память.set('подкидной-дурак:адрес-сервера', 'http://127.0.0.1:8799');
  const окно = {
    location: { search: настройки.поиск || '', protocol: 'https:', href: 'https://пример/Games/',
                origin: 'https://пример', pathname: '/Games/', host: 'пример' },
    localStorage: памятьБраузера, sessionStorage: памятьБраузера,
    addEventListener: function () {},
    navigator: { clipboard: { writeText: function (т) { буфер.текст = т; return Promise.resolve(); } } },
    Telegram: { WebApp: приложение }
  };
  const страница = { getElementById: function () { return null; }, addEventListener: function () {},
                     querySelectorAll: function () { return []; }, readyState: 'complete' };
  const окружение = {
    window: окно, document: страница, console: { warn: function () {}, log: console.log, error: console.error },
    fetch: function (адрес, н) {
      тела.push({ адрес: адрес, тело: JSON.parse(н.body || '{}') });
      const ответ = настройки.сервер || { умеем: true, ок: false };
      return Promise.resolve({ ok: true, status: 200, json: function () { return Promise.resolve(ответ); } });
    },
    setTimeout: setTimeout, clearTimeout: clearTimeout, setInterval: setInterval, clearInterval: clearInterval,
    URLSearchParams: URLSearchParams, URL: URL, AbortController: AbortController,
    Promise: Promise, JSON: JSON, Date: Date, Math: Math
  };
  окружение.globalThis = окружение;
  vm.runInNewContext(fs.readFileSync(path.join(КОРЕНЬ, 'js/сеть.js'), 'utf8'), окружение, { filename: 'js/сеть.js' });
  return { окно: окно, тела: тела, буфер: буфер, открытые: открытые, показанные: показанные };
}

(async function () {
  // А. Поверх игры: сервер готов, человек выбрал чат.
  const а = собратьОкно({ поверх: true, отправит: true, сервер: { умеем: true, ок: true, номерСообщения: 'м-1' } });
  const итогА = await а.окно.Сеть.похвастаться(описание);
  console.log('   поверх: ' + JSON.stringify(итогА) + ', серверу ушло: ' + JSON.stringify(а.тела[0] && а.тела[0].тело));
  проверить('поверх: отправлено', итогА.отправлено === true && итогА.способ === 'поверх');
  проверить('shareMessage позван с номером сервера', а.показанные[0] === 'м-1');
  const тело = а.тела[0] && а.тела[0].тело;
  проверить('серверу ушли вид «победа» и поля, а не слова',
    тело && тело.вид === 'победа' && тело.игра === 'дурак' && тело.игроков === 6 && тело.уровень === 'сложный' && тело.слова === undefined);
  проверить('ссылка — на приложение, без кода', тело && /^https:\/\/t\.me\/[A-Za-z0-9_]+\/[A-Za-z0-9_]+$/.test(тело.ссылка));
  проверить('подпись приложена', тело && тело.initData === 'user=%7B%22id%22%3A1%7D&hash=abc');

  // Б. Поверх игры, человек закрыл выбор — не отправлено, но способ «поверх».
  const б = собратьОкно({ поверх: true, отправит: false, сервер: { умеем: true, ок: true, номерСообщения: 'м-2' } });
  const итогБ = await б.окно.Сеть.похвастаться(описание);
  проверить('закрыл выбор: не отправлено, способ «поверх»', итогБ.отправлено === false && итогБ.способ === 'поверх');

  // В. Сервер не смог — на телефоне уходим в список чатов с готовыми словами.
  const в = собратьОкно({ поверх: true, отправит: true, сервер: { умеем: true, ок: false }, платформа: 'ios' });
  const итогВ = await в.окно.Сеть.похвастаться(описание);
  console.log('   по-старинке на телефоне: ' + JSON.stringify(итогВ) + ' → ' + decodeURIComponent(в.открытые[0] || ''));
  проверить('телефон: список чатов ссылкой', итогВ.способ === 'чат' && /t\.me\/share\/url/.test(в.открытые[0] || ''));
  проверить('в списке чатов — слова игры и ссылка без кода',
    decodeURIComponent(в.открытые[0] || '').indexOf(описание.слова) !== -1 && !/startapp/.test(в.открытые[0] || ''));

  // Г. Компьютер без shareMessage — буфер обмена.
  const г = собратьОкно({ поверх: false, платформа: 'tdesktop' });
  const итогГ = await г.окно.Сеть.похвастаться(описание);
  console.log('   компьютер: ' + JSON.stringify(итогГ) + ', в буфере: ' + г.буфер.текст);
  проверить('компьютер: буфер', итогГ.способ === 'буфер' && итогГ.отправлено === false);
  проверить('в буфере слова и ссылка', г.буфер.текст && г.буфер.текст.indexOf(описание.слова + ' https://t.me/') === 0);
  проверить('на сервер при этом не ходили', г.тела.length === 0);

  // Д. Пустое описание — не срывается.
  const д = собратьОкно({ поверх: false, платформа: 'tdesktop' });
  const итогД = await д.окно.Сеть.похвастаться(null);
  проверить('без описания — не срывается, слова по умолчанию', итогД.способ === 'буфер' && /Победа в подкидном дураке\. Сыграем\?/.test(д.буфер.текст));

  console.log(всёХорошо ? 'ИТОГ: всё сошлось.' : 'ИТОГ: есть беды.');
  process.exit(всёХорошо ? 0 : 1);
})();
