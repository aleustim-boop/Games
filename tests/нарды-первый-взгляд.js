const спать = (мс) => new Promise((ф) => setTimeout(ф, мс));

/** Нажать узел по имени; отвечает, нашёлся ли он и можно ли было нажать.
    Работает даже для скрытых предков, в отличие от Playwright.click(). */
async function нажать(страница, имя) {
  return страница.evaluate(function (имяУзла) {
    const узел = document.getElementById(имяУзла);
    if (!узел) return 'нет такого';
    if (узел.disabled) return 'выключен';
    if (узел.classList.contains('скрыт')) return 'спрятан';
    узел.click();
    return 'нажали';
  }, имя);
}

async function новаяСтраница(браузер, ш, в) {
  const окно = await браузер.newContext({ viewport: { width: ш, height: в }, hasTouch: true, deviceScaleFactor: 2 });
  const страница = await окно.newPage();
  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
    красные.push('консоль: ' + м.text());
  });
  await подготовитьПодделку(страница, { версия: '8.0', полныйЭкран: 'дают' });
  await страница.goto(АДРЕС);
  await спать(700);
  return { окно, страница, красные };
}

/** Наблюдатель за доской: кладём один раз, включаем на время хода. */
async function поставитьНаблюдателя(страница) {
  await страница.evaluate(() => {
    window.__слежка = { снимки: [], таймер: null };
    window.__снять = function () {
      const шашки = [...document.querySelectorAll('.шашка')];
      const едут = шашки.filter((ш) => ш.classList.contains('шашка--едет'));
      /* Раньше границей служил родитель «.бар» целиком — но в
         style-нарды.css у него «position: static», а обе половины внутри
         («.бар__половина») стоят «position: absolute» и потому НЕ входят
         в его коробку: у «.бар» getBoundingClientRect().height = 0, он
         схлопнут, а сами половины (где реально лежат шашки) геометрически
         ниже этой нулевой полоски. Совпадение середины шашки с границами
         такого «.бар» невозможно ни при какой паузе — проверка молчала
         не из-за медленной игры, а из-за неверного узла. Берём границы
         КАЖДОЙ половины бара по отдельности (нашёл диагностикой: снимок
         geometrии показал .бар={height:0}, .бар--чёрные — обычный
         прямоугольник заметно ниже). */
      const половиныБара = [...document.querySelectorAll('.бар__половина')];
      const наБаруПоРазметке = document.querySelectorAll('.бар .шашка');
      /* Считаем не «числится ли шашка в баре по разметке», а ВИДНА ли она
       * там глазом: пока она едет, она может уже принадлежать бару, но
       * стоять ещё на своём пункте. Раньше стенд считал по разметке — и
       * получал «улетела раньше, чем прилетела бьющая». */
      let наБаре = 0;
      naБарПодсчёт: for (const ш of наБаруПоРазметке) {
        const к = ш.getBoundingClientRect();
        const серединаX = к.left + к.width / 2;
        const серединаY = к.top + к.height / 2;
        const внутриКакойТоПоловины = половиныБара.some((п) => {
          const пКрая = п.getBoundingClientRect();
          return серединаX >= пКрая.left - 2 && серединаX <= пКрая.right + 2 &&
                 серединаY >= пКрая.top - 2 && серединаY <= пКрая.bottom + 2;
        });
        if (внутриКакойТоПоловины) наБаре++;
      }
      const наБареПоРазметке = наБаруПоРазметке.length;
      /* Положение едущих — с точностью до точки: если оно меняется
         несколько раз подряд, значит шашка ехала, а не прыгнула. */
      const где = едут.map((ш) => {
        const к = ш.getBoundingClientRect();
        return Math.round(к.left) + ',' + Math.round(к.top);
      }).join(' | ');
      return { едет: едут.length, где: где, наБаре: наБаре, поРазметке: наБареПоРазметке, всего: шашки.length };
    };
    window.__начать = function () {
      window.__слежка.снимки = [];
      const начало = performance.now();
      window.__слежка.таймер = setInterval(function () {
        const с = window.__снять();
        с.когда = Math.round(performance.now() - начало);
        const было = window.__слежка.снимки;
        const прошлый = было[было.length - 1];
        if (!прошлый || прошлый.где !== с.где || прошлый.едет !== с.едет || прошлый.наБаре !== с.наБаре) было.push(с);
      }, 40);
    };
    window.__кончить = function () { clearInterval(window.__слежка.таймер); return window.__слежка.снимки; };
  });
}

/** Сделать один ход пальцем: поднять шашку и пойти на подсвеченный пункт. */
/**
 * Дождаться, пока после броска кубиков появится, чем ходить.
 * Кубики катятся полторы секунды, и всё это время подсветки нет вовсе.
 * Стенд ждал полсекунды, не находил ни одной шашки «можно взять»
 * и уходил дальше, не сделав ни одного хода, — а жаловался при этом
 * на игру («сравнить темп нечем»).
 */
/**
 * Разбить снимки на отдельные ПРОЕЗДЫ шашек.
 *
 * Зачем. Сравнивать «сколько всего ехало у меня» со «сколько всего ехало
 * у бота» бессмысленно: за один заход человек двигает две шашки, бот —
 * одну или четыре, и общая длительность говорит про число ходов, а не
 * про темп. Поэтому считаем длительность ОДНОГО проезда: снимки с едущей
 * шашкой идут подряд, разрыв между ними — граница между ходами.
 */
function проезды(снимки) {
  const куски = [];
  let текущий = null;
  for (const с of снимки) {
    if (с.едет > 0) {
      if (!текущий) текущий = { начало: с.когда, конец: с.когда, положений: 0 };
      текущий.конец = с.когда;
      текущий.положений++;
    } else if (текущий) { куски.push(текущий); текущий = null; }
  }
  if (текущий) куски.push(текущий);
  return куски.map(function (к) {
    return { мс: к.конец - к.начало, положений: к.положений };
  }).filter(function (к) { return к.положений >= 2; });
}

async function дождатьсяХодов(страница, потолокМс) {
  const начало = Date.now();
  while (Date.now() - начало < (потолокМс || 5000)) {
    const есть = await страница.evaluate(() =>
      document.querySelectorAll('.шашка--можно-взять, .пункт--можно').length > 0);
    if (есть) return Date.now() - начало;
    await спать(100);
  }
  return -1;
}

