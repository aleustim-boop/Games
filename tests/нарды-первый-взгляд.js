/* ---------------------------------------------------------------------
   ЛОМАЮЩИЙ ЗАПУСК: копия игры/нарды/нарды-правила.js во временной папке ОС
   (не в проекте) с вырезанной строкой, которая ставит побитую шашку
   на бар. Настоящий файл не трогаем ни секунды — читаем с диска,
   портим строку в памяти, пишем результат во временную папку и
   подсовываем эту копию браузеру через page.route.
   Приём и уборка — те же, что в tests/витрина-все-плитки-видны.js. */
const ВСЕ_ВРЕМЕННЫЕ_ПАПКИ = [];
function новаяВременнаяПапка(префикс) {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), префикс));
  ВСЕ_ВРЕМЕННЫЕ_ПАПКИ.push(папка);
  return папка;
}
function прибратьВременныеПапки() {
  const корзинаОС = path.resolve(os.tmpdir());
  for (const папка of ВСЕ_ВРЕМЕННЫЕ_ПАПКИ) {
    try {
      const полныйПуть = path.resolve(папка);
      if (полныйПуть.indexOf(корзинаОС) !== 0) continue; // подстраховка: только внутри временной папки ОС
      fs.rmSync(полныйПуть, { recursive: true, force: true });
    } catch (сбой) { /* не убралось — не беда, это не портит результат проверки */ }
  }
}
process.on('exit', прибратьВременныеПапки);

function подготовитьИспорченнуюКопиюПравил() {
  const исходный = path.join(КОРЕНЬ, 'игры', 'нарды', 'нарды-правила.js');
  const текст = fs.readFileSync(исходный, 'utf8');
  const метка = 'партия.бар[соперник(цвет)].push(ш.побита);';
  if (текст.indexOf(метка) === -1) {
    throw new Error('--сломать: в игры/нарды/нарды-правила.js не нашлась строка «' + метка +
      '» — приём устарел (правила переписали), поправьте метку здесь же, в tests/нарды-первый-взгляд.js.');
  }
  const испорченный = текст.replace(метка, '/* --сломать: постановка сбитой шашки на бар вырезана нарды-первый-взгляд.js */');
  const папка = новаяВременнаяПапка('нарды-бой-сломать-');
  const файл = path.join(папка, 'нарды-правила.js');
  fs.writeFileSync(файл, испорченный, 'utf8');
  return файл;
}

/** Подмена /игры/нарды/нарды-правила.js испорченной копией. Маршрут — функцией-приметой
    с ручным раскодированием адреса (кириллица в имени файла шлётся процентами —
    та же ловушка, что описана в tests/браузер-робот.js и уже решена в
    tests/витрина-все-плитки-видны.js): регулярка на «сырой» адрес её бы не поймала. */
async function подключитьЛомающиеПравила(страница, путьКопии) {
  await страница.route((url) => {
    let адрес;
    try { адрес = decodeURIComponent(url.href); } catch (ошибка) { адрес = url.href; }
    return /\/игры\/нарды\/нарды-правила\.js(?:\?|$)/.test(адрес);
  }, async (маршрут) => {
    const тело = fs.readFileSync(путьКопии, 'utf8');
    await маршрут.fulfill({ status: 200, contentType: 'text/javascript; charset=utf-8', body: тело });
  });
}

