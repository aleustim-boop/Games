/**
 * Позиция, где бой на ближайшем ходу НЕИЗБЕЖЕН (а не «может повезти»).
 *
 * Крючок — window.НардыПравила: игры/нарды/нарды-экран.js в самом начале файла
 * держит константную ссылку `const Правила = window.НардыПравила`, так
 * что подмена свойств ОБЪЕКТА видна экрану сразу, без перезагрузки
 * страницы (тот же приём уже применялся в
 * tests/нарды-подсказка-почему-не-ходит.js для создатьПартию/бросить).
 *
 * Позиция (короткие нарды, ходят белые, дубль 1-1): у белых один
 * осмысленный ход вообще — 6→5, и он бьёт одинокую чёрную шашку;
 * второй возможный отправитель, куча на 24, упирается шагом 1 в пункт
 * 23, который держат ДВЕ чёрные шашки (закрыт) — значит случайный
 * тычок пальцем (tests ходит вслепую, .шашка--можно-взять один из
 * доступных) промахнуться мимо боя не может.
 *
 * Возвращает в меню (если экран партии уже открыт), выбирает короткие
 * нарды и жмёт «кнопка-вдвоём» — партия стартует уже с этой позиции.
 */
async function поставитьБойНаверняка(страница) {
  /* «Кнопка-в-меню» ведёт в разные места смотря по тому, догрузилось ли
     уже лобби (игры/нарды/нарды-экран.js, функция вМеню): пока не догрузилось —
     на «экран-режимов» (тот же первый экран, что и сразу после захода),
     а после догрузки — в «экран-лобби» с карточками входа, откуда до
     версии-короткие отдельная дорога. Проверено прогоном: после того как
     тест уже поиграл, клик по «кнопка-в-меню» не открывал ни
     версия-короткие, ни кнопка-вдвоём — обе оставались вне видимости, и
     форсированная позиция не подставлялась. Перезагрузка страницы
     повторяет ГАРАНТИРОВАННО рабочий путь: первый экран после
     goto/reload — «экран-режимов», как в самом начале этого файла. */
  await страница.reload();
  await спать(700);
  await поставитьНаблюдателя(страница);
  await нажать(страница, 'версия-короткие');
  await спать(400);
  await страница.evaluate(() => {
    const П = window.НардыПравила;
    if (!window.__настоящийБросокБоя) window.__настоящийБросокБоя = П.бросить;
    П.создатьПартию = function () {
      return П.партияИзРасстановки(П.КОРОТКИЕ, {
        ходит: П.БЕЛЫЕ,
        белые: { 24: 14, 6: 1 },
        чёрные: { 23: 2, 5: 1, 19: 12 }
      });
    };
    П.бросить = function (партия) { return window.__настоящийБросокБоя(партия, [1, 1]); };
    /* Диагностика для раздела «Бой и бар»: захватываем ссылку на живой
       объект партии в window.__партияПодСлежкой, чтобы после хода можно
       было спросить у САМИХ правил (не у геометрии DOM), сколько шашек
       на баре — если наблюдатель по CSS соврёт, здесь будет видно. */
    if (!window.__настоящийСделатьШаг) window.__настоящийСделатьШаг = П.сделатьШаг;
    П.сделатьШаг = function (партия, шаг) {
      window.__партияПодСлежкой = партия;
      return window.__настоящийСделатьШаг(партия, шаг);
    };
  });
  await нажать(страница, 'кнопка-вдвоём');
  await спать(800);
  const диагностика = await страница.evaluate(() => {
    const видимый = document.querySelector('.экран--виден');
    return {
      экран: видимый ? видимый.id : 'нет',
      можноВзять: document.querySelectorAll('.шашка--можно-взять').length,
      можноПункт: document.querySelectorAll('.пункт--можно').length,
      подменаСработала: window.НардыПравила && window.НардыПравила.создатьПартию.toString().indexOf('КОРОТКИЕ') !== -1
    };
  });
  console.log('  [диагностика] экран=' + диагностика.экран + ', можно-взять=' + диагностика.можноВзять +
    ', пункт-можно=' + диагностика.можноПункт + ', подмена-приросла=' + диагностика.подменаСработала);
}

/** Один круг: бросить (если надо), замерить бар до и после хода, попробовать
    закончить ход. Возвращает {было, стало, снимки, что}. Общая часть цикла
    боя — используется и обычным прогоном, и ломающим (--сломать).
    Диагностические поля (надоБросить, можноВзятьДо, можноПунктДо, бросокЕсть)
    для раздела «Бой и бар» ниже — печатать их или нет, решает вызывающий. */
async function кругБоя(страница) {
  const надоБросить = await страница.evaluate(() => {
    const к = document.getElementById('кнопка-бросить');
    return !!(к && к.offsetParent !== null);
  });
  if (надоБросить) { await страница.click('#кнопка-бросить'); await спать(400); }
  /* Окно наблюдения открываем РОВНО перед ходом: раньше оно захватывало
     хвост прошлого движения, и «побитая улетела раньше» могло померещиться. */
  const было = await страница.evaluate(() => window.__снять().наБаре);
  await страница.evaluate(() => window.__начать());
  const доХода = await страница.evaluate(() => ({
    можноВзять: document.querySelectorAll('.шашка--можно-взять').length,
    можноПункт: document.querySelectorAll('.пункт--можно').length,
    кнопкаБросить: (function () {
      const к = document.getElementById('кнопка-бросить');
      return !!(к && к.offsetParent !== null);
    })()
  }));
  const что = await ходПальцем(страница);
  /* Паузы разные по смыслу хода. «Пошли» — это реальный шаг: по расчёту
     (ТЕМП_СВОЙ.переезд=220 + ПАУЗА_ПЕРЕД_ОТЛЁТОМ_ПОБИТОЙ=130 в
     игры/нарды/нарды-экран.js) побитая должна долететь на бар к ~350 мс, но
     диагностика (см. ниже, «[диагностика +1500мс]») поймала её ГЕОМЕТРИЮ
     на баре не в 700 мс, а заметно позже — headless-браузер откладывает
     тики requestAnimationFrame сильнее расчёта. 700 мс — было мало и
     проверка не успевала заметить настоящий, уже случившийся бой; берём
     с запасом. «Подняли»/«нечего» — там просто подсветка, ждать долго
     незачем. */
  await спать(что === 'нечего' ? 250 : что === 'пошли' ? 2000 : 400);
  const снимки = await страница.evaluate(() => window.__кончить());
  const стало = снимки.length ? снимки[снимки.length - 1].наБаре : было;
  const кончить = await страница.evaluate(() => {
    const к = document.getElementById('кнопка-закончить-ход');
    if (к && к.offsetParent !== null) { к.click(); return true; }
    return false;
  });
  if (кончить) await спать(500);
  return { было, стало, снимки, что, надоБросить, доХода };
}

