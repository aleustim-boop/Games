async function дождаться(страница, экран, мс) {
  await страница.waitForFunction((и) => {
    const э = document.querySelector('.экран.экран--виден');
    return Boolean(э && э.id === и);
  }, экран, { timeout: мс || 8000 });
}
async function нажать(страница, локатор) {
  await локатор.first().click({ timeout: 5000 });
}
async function дойтиДоКомнаты(страница) {
  await страница.waitForSelector('#кнопка-игра-дурак', { state: 'visible', timeout: 8000 });
  await нажать(страница, страница.locator('#кнопка-игра-дурак'));
  await дождаться(страница, 'экран-лобби');
  await нажать(страница, страница.locator('#лобби-играть-онлайн'));
  await дождаться(страница, 'экран-открытые-столы');
  await нажать(страница, страница.locator('#открытые-столы-создать'));
  await дождаться(страница, 'экран-путь-правила');
  await нажать(страница, страница.locator('.экран.экран--виден [data-путь="далее"]'));
  await дождаться(страница, 'экран-путь-игроки');
  await нажать(страница, страница.locator('#путь-числа .числа__число',
    { hasText: new RegExp('^\\s*' + МАКС_ИГРОКОВ + '\\s*$') }));
  await нажать(страница, страница.locator('.экран.экран--виден [data-путь="далее"]'));
  await дождаться(страница, 'экран-путь-настройки');
  await нажать(страница, страница.locator('#путь-начать'));
  await дождаться(страница, 'экран-комнаты', 10000);
  await страница.waitForSelector('#комната:not(.скрыт)', { timeout: 10000 });
  await страница.waitForSelector('.рассадка__место--свободно', { timeout: 10000 });
}

/* ---------------------------------------------------------------------
   Замер кнопки «Выйти из комнаты» — scrollTop экрана явно обнуляется
   перед замером: проверяем именно «видно без прокрутки».
   --------------------------------------------------------------------- */
async function замеритьКнопкуОтмена(страница) {
  return страница.evaluate(() => {
    const прокручиваемый = document.getElementById('экран-комнаты');
    if (прокручиваемый) прокручиваемый.scrollTop = 0;
    const узел = document.getElementById('кнопка-комната-отмена');
    if (!узел) return { найдено: false };
    const rect = узел.getBoundingClientRect();
    return {
      найдено: true,
      bottom: rect.bottom,
      top: rect.top,
      innerHeight: window.innerHeight,
      offsetParentЕсть: узел.offsetParent !== null
    };
  });
}

/* ---------------------------------------------------------------------
   Один прогон целиком — по всем трём ширинам.
   --------------------------------------------------------------------- */
async function прогнать(подменаStyleCss, метка) {
  const строки = [];
  const проваленныеИмена = [];
  let провалов = 0;
  function проверить(имя, условие, детали) {
    строки.push((условие ? '  ок    — ' : '  ПЛОХО — ') + имя + (детали ? ' (' + детали + ')' : ''));
    if (!условие) { провалов++; проваленныеИмена.push(имя); }
  }

  const порты = [];
  const портИгры = await выбратьСвободныйПорт(порты); порты.push(портИгры);
  const портСтраниц = await выбратьСвободныйПорт(порты); порты.push(портСтраниц);
  console.log('  [' + метка + '] порт игры (сервер комнат, в памяти): ' + портИгры + ', порт страниц: ' + портСтраниц +
    ' (' + (подменаStyleCss !== null ? 'style.css подменён испорченной копией из temp' : 'style.css родной, с диска проекта') + '), игроков за столом: ' + МАКС_ИГРОКОВ);

  сервера.оснасткаДляПроверки(ТОКЕН, поддельныйTelegram);
  const сервер = сервера.создатьСервер();
  await new Promise(function (готово, беда) {
    сервер.once('error', беда);
    сервер.listen(портИгры, АДРЕС_ХОЗЯИНА, готово);
  });

  const сервисСтраниц = await поднятьСерверСтраниц(портСтраниц, подменаStyleCss);

  let браузер = null;
  const снимки = [];

  try {
    браузер = await chromium.launch();

    for (let индекс = 0; индекс < ШИРИНЫ.length; индекс++) {
      const размер = ШИРИНЫ[индекс];
      const хозяинЭтойШирины = ХОЗЯИН_БАЗА + индекс;
      const метка_ширины = размер.width + 'x' + размер.height;
      const контекст = await браузер.newContext({ viewport: размер, hasTouch: true, deviceScaleFactor: 2 });
      const страница = await контекст.newPage();
      const красные = [];
      страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
      страница.on('console', (м) => {
        if (м.type() !== 'error') return;
        const текст = м.text();
        const л = м.location && м.location();
        const откуда = (л && л.url) || '';
        const вместе = текст + ' ' + откуда;
        if (/telegram-web-app\.js|telegram\.org/.test(вместе)) return;
        // Тестовый сервер комнат в памяти работает без настоящего токена
        // Telegram — дверь «/фото/…» у него всегда отвечает 404 (см.
        // server/фото-игроков.js, «умею()»). Тот же шум есть и в
        // tests/позвать-в-комнате.js — не поломка ЭТОЙ проверки, а
        // особенность тестового окружения без сети до настоящего Telegram.
        let декодировано = вместе;
        try { декодировано = decodeURIComponent(вместе); } catch (е) { /* не страшно */ }
        if (/status of 404.*\/фото\//.test(декодировано)) return;
        красные.push('консоль: ' + текст + (откуда ? ' (' + откуда + ')' : ''));
      });

      await подготовитьПодделку(страница, { версия: '8.0', подпись: подписатьInitData({ id: хозяинЭтойШирины, first_name: 'Хозяин' }) });
      const адрес = 'http://' + АДРЕС_ХОЗЯИНА + ':' + портСтраниц + '/index.html?сервер=' +
        encodeURIComponent('http://' + АДРЕС_ХОЗЯИНА + ':' + портИгры);
      await страница.goto(адрес, { waitUntil: 'domcontentloaded' });

      let дошли = true;
      try {
        await дойтиДоКомнаты(страница);
      } catch (ошибка) {
        дошли = false;
        console.log('  [' + метка + '/' + метка_ширины + '] не дошёл до комнаты: ' + (ошибка && ошибка.message || ошибка));
      }
      проверить('дошли до комнаты ожидания (' + метка_ширины + ')', дошли);

      if (дошли) {
        const замер = await замеритьКнопкуОтмена(страница);
        проверить('кнопка «Выйти из комнаты» найдена на странице (' + метка_ширины + ')', замер.найдено === true);
        if (замер.найдено) {
          console.log('  [' + метка + '/' + метка_ширины + '] кнопка: top=' + замер.top.toFixed(1) +
            ', bottom=' + замер.bottom.toFixed(1) + ', высота окна=' + замер.innerHeight +
            ', offsetParent есть=' + замер.offsetParentЕсть);
          проверить('нижний край кнопки внутри окна без прокрутки (' + метка_ширины + ')',
            замер.bottom <= замер.innerHeight + 0.5,
            'bottom=' + замер.bottom.toFixed(1) + 'px, высота окна=' + замер.innerHeight + 'px');
          проверить('кнопка не спрятана (offsetParent есть) (' + метка_ширины + ')', замер.offsetParentЕсть === true);
        } else {
          проверить('нижний край кнопки внутри окна без прокрутки (' + метка_ширины + ')', false, 'узел не найден');
          проверить('кнопка не спрятана (offsetParent есть) (' + метка_ширины + ')', false, 'узел не найден');
        }

        if (размер.width === 390 && размер.height === 844) {
          if (!fs.existsSync(ПАПКА_СНИМКОВ)) fs.mkdirSync(ПАПКА_СНИМКОВ, { recursive: true });
          const файлСнимка = path.join(ПАПКА_СНИМКОВ,
            'комната-отмена-видна' + (метка === 'сломано' ? '-сломано' : '') + '.png');
          await страница.screenshot({ path: файлСнимка });
          снимки.push(файлСнимка);
          console.log('  [' + метка + '] снимок 390×844: ' + файлСнимка);
        }
      } else {
        проверить('кнопка «Выйти из комнаты» найдена на странице (' + метка_ширины + ')', false, 'до комнаты не дошли');
        проверить('нижний край кнопки внутри окна без прокрутки (' + метка_ширины + ')', false, 'до комнаты не дошли');
        проверить('кнопка не спрятана (offsetParent есть) (' + метка_ширины + ')', false, 'до комнаты не дошли');
      }

      проверить('консоль браузера чистая (' + метка_ширины + ')', красные.length === 0,
        красные.length ? красные.join(' | ') : '');

      await контекст.close();
    }

    await браузер.close();
    браузер = null;
  } finally {
    if (браузер) { try { await браузер.close(); } catch (е) { /* уже закрыт */ } }
    сервера.оснасткаДляПроверки();
    await new Promise((р) => сервер.close(р));
    await new Promise((р) => сервисСтраниц.close(р));
    try { fs.rmSync(process.env.ДАННЫЕ_ИГРЫ, { recursive: true, force: true }); } catch (е) { /* не страшно */ }
  }

  return { строки, провалов, проваленныеИмена, снимки };
}

