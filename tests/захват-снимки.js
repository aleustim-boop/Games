/* Пилюля-подсказка #захват-совет в первой партии: память чистая (ключа «выучено» нет),
   «Играть с ботами» сразу ведёт в партию. Не найдена или невидима — провал. */
async function проверитьСоветы(браузер, порт, ш, в) {
  console.log('\n=== Подсказки первой партии, ширина ' + ш + '×' + в + ' ===');
  const контекст = await браузер.newContext({ viewport: { width: ш, height: в } });
  const страница = await контекст.newPage();
  await подготовитьПодделку(страница, {});
  const ошибки = [];
  страница.on('console', с => {
    if (с.type() === 'error' && (с.location().url || '').indexOf('telegram-web-app.js') === -1) ошибки.push(с.text());
  });
  страница.on('pageerror', е => ошибки.push('необработанная ошибка: ' + е.message));
  await страница.goto('http://127.0.0.1:' + порт + '/захват.html', { waitUntil: 'load' });
  await страница.waitForTimeout(800);
  // Память чистая: ключ не выставлен (подделка Telegram хранит его в localStorage или CloudStorage — стираем оба).
  await страница.evaluate(() => { try { localStorage.removeItem('zahvat-learned'); } catch (_) { /* пусто */ } });
  await страница.reload({ waitUntil: 'load' });
  await страница.waitForTimeout(800);
  const ключДо = await страница.evaluate(() => localStorage.getItem('zahvat-learned'));
  проверить(!ключДо || ключДо === '0', 'советы ' + ш + ': память чистая, ключ «выучено» не выставлен (' + ключДо + ')');

  await страница.click('#захват-боты');
  await страница.waitForTimeout(800);
  const столВидно = await страница.evaluate(() => document.getElementById('экран-игры').classList.contains('экран--виден'));
  проверить(столВидно, 'советы ' + ш + ': «Играть с ботами» в чистой памяти сразу открыла стол (первая партия)');
  const ключПосле = await страница.evaluate(() => localStorage.getItem('zahvat-learned'));
  проверить(ключПосле === '1', 'советы ' + ш + ': ключ «выучено» записан на старте первой партии (' + ключПосле + ')');

  // Состояние пилюли: ноль найденного или невидима = провал.
  const пилюля = () => страница.evaluate(() => {
    const у = document.getElementById('захват-совет');
    if (!у) return { есть: false };
    const р = у.getBoundingClientRect();
    const т = document.getElementById('захват-совет-текст');
    const п = document.querySelector('.захват-панель-действий');
    const рп = п ? п.getBoundingClientRect() : null;
    const кнопка = document.getElementById('захват-совет-понятно');
    const рк = кнопка.getBoundingClientRect();
    return {
      есть: true,
      видна: !у.classList.contains('скрыт') && getComputedStyle(у).display !== 'none'
        && getComputedStyle(у).visibility !== 'hidden' && р.width > 0 && р.height > 0,
      текст: (т.textContent || '').trim(),
      влезает: р.left >= 0 && р.right <= window.innerWidth && р.top >= 0 && р.bottom <= window.innerHeight,
      обрезан: т.scrollWidth > т.clientWidth + 1 || у.scrollHeight > у.clientHeight + 1,
      налезаетНаПанель: !!рп && р.bottom > рп.top && р.top < рп.bottom,
      кнопкаНажимаема: рк.width >= 32 && рк.height >= 32 && рк.right <= window.innerWidth,
      р: [Math.round(р.left), Math.round(р.top), Math.round(р.width), Math.round(р.height)]
    };
  });
  const п1 = await пилюля();
  проверить(п1.есть && п1.видна && п1.текст.length > 0, 'советы ' + ш + ': первая пилюля #захват-совет найдена, видна, текст «' + (п1.текст || '') + '»'
    + (п1.есть ? ' [x,y,ширина,высота: ' + п1.р.join(', ') + ']' : ': узла нет'));
  if (п1.есть && п1.видна) {
    проверить(п1.влезает, 'советы ' + ш + ': пилюля целиком в окне');
    проверить(!п1.обрезан, 'советы ' + ш + ': текст пилюли не обрезан');
    проверить(!п1.налезаетНаПанель, 'советы ' + ш + ': пилюля не перекрывает панель «Отменить / Готово»');
    проверить(п1.кнопкаНажимаема, 'советы ' + ш + ': кнопка «Понятно» не меньше 32 точек и в окне');
  }
  await страница.screenshot({ path: path.join(ПАПКА_СНИМКОВ.replace(/захват$/, ''), 'захват-совет-' + ш + '.png') });

  // Следующая пилюля: после «Готово» подсказка меняется на текст про раскрытие раунда.
  await страница.click('#захват-готово');
  await страница.waitForTimeout(400);
  if (await страница.evaluate(() => { const у = document.getElementById('захват-остаток'); return !!у && !у.classList.contains('скрыт'); })) {
    await страница.click('#захват-остаток-да', { timeout: 4000 }).catch(() => {});
  }
  const сменилась = await страница.waitForFunction(т => {
    const у = document.getElementById('захват-совет');
    const х = (document.getElementById('захват-совет-текст').textContent || '').trim();
    return !!у && !у.classList.contains('скрыт') && х.length > 0 && х !== т;
  }, п1.текст, { timeout: 6000 }).then(() => true, () => false);
  const п2 = await пилюля();
  проверить(сменилась && п2.есть && п2.видна, 'советы ' + ш + ': следующая пилюля (после «Готово») видна, текст «' + (п2.текст || '') + '»');
  if (п2.есть && п2.видна) {
    проверить(п2.влезает && !п2.обрезан, 'советы ' + ш + ': вторая пилюля целиком в окне и не обрезана');
  }
  await страница.screenshot({ path: path.join(ПАПКА_СНИМКОВ.replace(/захват$/, ''), 'захват-совет-2-' + ш + '.png') });

  // «Понятно» гасит пилюлю.
  if (п2.есть && п2.видна) {
    await страница.click('#захват-совет-понятно');
    await страница.waitForTimeout(200);
    const п3 = await пилюля();
    проверить(!п3.видна, 'советы ' + ш + ': «Понятно» убрало пилюлю');
  }
  проверить(ошибки.length === 0, 'советы ' + ш + ': консоль без ошибок' + (ошибки.length ? ': ' + ошибки.join(' | ') : ''));
  await контекст.close();
}

async function главная() {
  fs.mkdirSync(ПАПКА_СНИМКОВ, { recursive: true });
  const сервер = await поднятьСервер(копия);
  const порт = сервер.address().port;
  console.log('Сервер проверки: порт ' + порт + ', PID ' + process.pid + (копия ? ', копия: ' + копия : ''));
  const браузер = await chromium.launch();
  try {
    for (const [ш, в] of РАЗМЕРЫ) {
      console.log('\n=== Ширина ' + ш + '×' + в + ' ===');
      const контекст = await браузер.newContext({ viewport: { width: ш, height: в } });
      const страница = await контекст.newPage();
      await подготовитьПодделку(страница, {});
      const ошибки = [];
      const сбои = [];
      let ответов = 0;
      // Скрипт telegram.org мы сами не пускаем (подделка вместо него) — его отказ не считается.
      страница.on('console', с => {
        const адрес = с.location().url || '';
        if (с.type() === 'error' && адрес.indexOf('telegram-web-app.js') === -1) ошибки.push(с.text() + ' ' + адрес);
      });
      страница.on('pageerror', е => ошибки.push('необработанная ошибка: ' + е.message));
      страница.on('response', о => { ответов++; if (о.status() >= 400) сбои.push(о.status() + ' ' + о.url()); });
      страница.on('requestfailed', з => {
        if (з.url().indexOf('telegram-web-app.js') === -1) сбои.push('сбой ' + з.url());
      });
      // Игрок не новичок — иначе первая партия уходит сразу в игру.
      await страница.addInitScript(() => { try { localStorage.setItem('zahvat-learned', '1'); } catch (_) { /* пусто */ } });
      await страница.goto('http://127.0.0.1:' + порт + '/захват.html', { waitUntil: 'load' });
      await страница.waitForTimeout(800);

      const загружена = (await страница.locator('#экран-лобби').count()) === 1;
      проверить(загружена && ответов > 0, 'страница загрузилась: есть #экран-лобби, ответов сервера: ' + ответов);

      const без_прокрутки = async (имя) => {
        const р = await страница.evaluate(() => ({ п: document.documentElement.scrollWidth, о: window.innerWidth }));
        проверить(р.п <= р.о, 'нет горизонтальной прокрутки (' + имя + '): ' + р.п + ' ≤ ' + р.о);
      };
      const снять = async (имя) => {
        await страница.screenshot({ path: path.join(ПАПКА_СНИМКОВ, имя + '-' + ш + '.png') });
      };

      // 1. Лобби
      await без_прокрутки('лобби');
      // Кнопки «Правила» в лобби нет (ноль узлов — это и есть зелёное).
      проверить((await страница.locator('#захват-правила-лобби').count()) === 0, 'в лобби нет кнопки «Правила» (#захват-правила-лобби)');
      // Три вкладки нижней полосы: каждая найдена, видна и с непустым текстом. Меньше трёх — провал.
      const вкладки = await страница.evaluate(() => ['захват-вкладка-игры', 'захват-вкладка-рейтинг', 'захват-вкладка-профиль'].map(ид => {
        const у = document.getElementById(ид);
        if (!у) return { ид: ид, есть: false, текст: '', видна: false };
        const р = у.getBoundingClientRect();
        return { ид: ид, есть: true, текст: (у.innerText || '').trim(), видна: getComputedStyle(у).display !== 'none' && р.width > 0 && р.height > 0 };
      }));
      const хорошихВкладок = вкладки.filter(в => в.есть && в.видна && в.текст.length > 0);
      проверить(хорошихВкладок.length === 3, 'в нижней полосе лобби три вкладки с видимым текстом: ' + хорошихВкладок.length + ' из 3 ('
        + вкладки.map(в => в.ид.replace('захват-вкладка-', '') + '=' + (в.есть ? '«' + в.текст + '»' + (в.видна ? '' : ' не видна') : 'нет узла')).join(', ') + ')');
      const полосаВЛобби = await страница.evaluate(() => {
        const н = document.querySelector('.нижние-вкладки');
        if (!н) return false;
        const р = н.getBoundingClientRect();
        return getComputedStyle(н).display !== 'none' && р.width > 0 && р.height > 0;
      });
      проверить(полосаВЛобби, 'нижняя полоса вкладок видна в лобби');
      // Низ лобби докручивается выше полосы вкладок: «Есть код?» целиком над ней, а не под ней.
      const низЛобби = await страница.evaluate(() => {
        const э = document.getElementById('экран-лобби');
        э.scrollTop = э.scrollHeight;
        const код = document.querySelector('#экран-лобби .деберц-пригласили');
        const полоса = document.querySelector('.нижние-вкладки');
        if (!код || !полоса) return null;
        return { низКода: Math.round(код.getBoundingClientRect().bottom), верхПолосы: Math.round(полоса.getBoundingClientRect().top) };
      });
      проверить(!!низЛобби && низЛобби.низКода <= низЛобби.верхПолосы, 'лобби: «Есть код?» докручивается выше нижней полосы'
        + (низЛобби ? ' (низ ' + низЛобби.низКода + ' ≤ верх полосы ' + низЛобби.верхПолосы + ')' : ': узел не найден'));
      await страница.evaluate(() => { document.getElementById('экран-лобби').scrollTop = 0; });
      await снять('1-лобби');

      // 2. Настройки с ботами
      await страница.click('#захват-боты');
      await страница.waitForTimeout(300);
      const настройкиВидны = await страница.evaluate(() => document.getElementById('захват-настройки').classList.contains('экран--виден'));
      проверить(настройкиВидны, 'кнопка «Играть с ботами» открыла настройки');
      await без_прокрутки('настройки');
      await снять('2-настройки');

      // 3. Пустой стол
      await страница.evaluate(() => {
        document.querySelectorAll('.экран').forEach(е => е.classList.toggle('экран--виден', е.id === 'экран-игры'));
      });
      await страница.waitForTimeout(300);
      await без_прокрутки('стол');
      const стол = await страница.evaluate(() => {
        const к = document.getElementById('захват-карта');
        const н = document.querySelector('.нижние-вкладки');
        const видна = !!н && getComputedStyle(н).display !== 'none' && н.getBoundingClientRect().height > 0
          && н.offsetParent !== null && getComputedStyle(н).visibility !== 'hidden';
        const шайбы = Array.from(document.querySelectorAll('.захват-шайба, .захват-пилюля'))
          .map(э => getComputedStyle(э).display);
        return { карта: к ? getComputedStyle(к).touchAction : null, видна, шайбы };
      });
      проверить(стол.карта === 'none', 'у #захват-карта touch-action = none (сейчас: ' + стол.карта + ')');
      проверить(стол.шайбы.every(д => д === 'none'), 'шайбы и пилюли скрыты: найдено ' + стол.шайбы.length + ', не скрыто ' + стол.шайбы.filter(д => д !== 'none').length);
      проверить(!стол.видна, 'нижняя полоса вкладок не видна на столе');
      await снять('3-пустой-стол');

      // 4. «Как играть» (только 360)
      if (ш === 360) {
        // Чистое лобби: перезагрузка (ручное переключение экранов оставляет игровой вид).
        await страница.reload({ waitUntil: 'load' });
        await страница.waitForTimeout(800);
        // Кнопки «Правила» в лобби больше нет: «Как играть» открывается из листа «⋯».
        // В Telegram своя «⋯» спрятана, лист открывает системный пункт «Настройки» — нажимаем его (как игрок).
        // Своя «⋯» видна — жмём её; нет — пункт Telegram.
        if (await страница.locator('#экран-лобби [data-меню]').isVisible()) {
          await страница.click('#экран-лобби [data-меню]');
        } else {
          const нажат = await страница.evaluate(() => {
            const т = window.ПоддельныйТелеграм;
            if (!т || typeof т.нажатьНастройки !== 'function') return false;
            т.нажатьНастройки();
            return true;
          });
          проверить(нажат, 'лист «⋯» открыт пунктом «Настройки» Telegram');
        }
        await страница.waitForTimeout(300);
        await страница.click('#кнопка-лист-игры-правила');
        await страница.waitForTimeout(400);
        const открыто = await страница.evaluate(() => { const д = document.getElementById('захват-справка'); return !!д && д.open; });
        проверить(открыто, 'окно «Как играть» открылось');
        await без_прокрутки('справка');
        await снять('4-как-играть');
      }

      // 5. Партия с ботами: раунд 1 после раздачи, раскрытие после «Готово», раунд 2. Дальше не играем.
      await страница.reload({ waitUntil: 'load' });
      await страница.waitForTimeout(800);
      await страница.click('#захват-боты');
      await страница.waitForTimeout(300);
      await страница.click('#захват-начать');
      await страница.waitForTimeout(800);
      const столВидно = await страница.evaluate(() => document.getElementById('экран-игры').classList.contains('экран--виден'));
      проверить(столВидно, 'после «Начать» открылся стол');
      const номерРаунда = () => страница.evaluate(() => (document.getElementById('захват-раунд').textContent || '').trim());
      const раунд1 = await номерРаунда();
      проверить(раунд1.length > 0, 'на столе подписан раунд: «' + раунд1 + '»');
      await без_прокрутки('стол, раунд 1');
      // Карта растёт на свободную высоту: панель действий прижата к низу окна (не выше 40 точек от края).
      const низПанели = await страница.evaluate(() => {
        const п = document.querySelector('.захват-панель-действий');
        return п ? Math.round(п.getBoundingClientRect().bottom) : -1;
      });
      проверить(низПанели >= в - 40 && низПанели <= в, 'стол: панель «Отменить / Готово» прижата к низу (низ ' + низПанели + ' из ' + в + ')');
      await снять('5-стол-раунд-1');

      // «Готово»; если стол спросил про остаток войск — отвечаем «Поставить и готово».
      await страница.click('#захват-готово');
      await страница.waitForTimeout(400);
      if (await страница.evaluate(() => { const у = document.getElementById('захват-остаток'); return !!у && !у.classList.contains('скрыт'); })) {
        const нажато = await страница.click('#захват-остаток-да', { timeout: 4000 }).then(() => true, () => false);
        проверить(нажато, 'ответ «Поставить и готово» на вопрос об остатке войск нажимается пальцем');
      }
      // Пластина итога появляется на каком-то шаге раскрытия (~8 с) — ждём её, но не дольше 15 с.
      const пластина = await страница.waitForFunction(() => {
        const п = document.getElementById('захват-пластина');
        return !!п && !п.classList.contains('скрыт') && п.textContent.trim().length > 0;
      }, null, { timeout: 15000 }).then(() => true, () => false);
      проверить(пластина, 'после «Готово» во время раскрытия появилась пластина итога раунда');
      // Раскрытие идёт: «Ждём…» тут быть не должно, счётчик готовых полный, кнопки панели заперты.
      const раскрытие = await страница.evaluate(() => ({
        подсказка: (document.getElementById('захват-подсказка').textContent || '').trim(),
        готовы: (document.getElementById('захват-готовы').textContent || '').trim(),
        готовоЗаперто: document.getElementById('захват-готово').disabled,
        отменитьЗаперто: document.getElementById('захват-отменить').disabled
      }));
      const готовыЧисла = /^Готовы ([0-9]+)[/]([0-9]+)$/.exec(раскрытие.готовы);
      проверить(раскрытие.подсказка.length > 0 && раскрытие.подсказка.indexOf('Ждём') !== 0, 'раскрытие: подсказка не начинается с «Ждём»: «' + раскрытие.подсказка + '»');
      проверить(!!готовыЧисла && готовыЧисла[1] === готовыЧисла[2], 'раскрытие: счётчик «' + раскрытие.готовы + '» — готовы все');
      проверить(раскрытие.готовоЗаперто && раскрытие.отменитьЗаперто, 'раскрытие: «Готово/Изменить» и «Отменить» заперты');
      await без_прокрутки('стол, раскрытие');
      await снять('6-стол-раскрытие-итог');

      // Ждём второй раунд: подпись раунда меняется.
      const второй = await страница.waitForFunction(п => (document.getElementById('захват-раунд').textContent || '').trim() !== п, раунд1, { timeout: 20000 }).then(() => true, () => false);
      проверить(второй, 'после раскрытия начался второй раунд (подпись: «' + (await номерРаунда()) + '»)');
      await страница.waitForTimeout(500);
      await без_прокрутки('стол, раунд 2');
      await снять('7-стол-раунд-2');

      // 6. Итог партии (В8б): из сохранения собираем законченную партию, где человек на 2-м месте
      // (области 8/6/4/2 по местам), и отдаём её в дверь экрана — так же, как это делают правила в миг конца.
      const собрано = await страница.evaluate(() => {
        const с = JSON.parse(localStorage.getItem('zahvat-save') || 'null');
        if (!с || !window.ЗахватПравила || !window.ЗахватЭкран) return false;
        const п = с.партия;
        const столицы = new Set(п.столицы.map(ст => ст.область));
        const простые = [];
        for (let н = 1; н < п.хозяева.length; н++) if (!столицы.has(н)) { простые.push(н); п.хозяева[н] = null; }
        const порядок = п.игроки.filter(к => к !== 'человек');
        порядок.splice(1, 0, 'человек');
        const сколько = [8, 6, 4, 2];
        let взято = 0;
        порядок.forEach((к, н) => { for (let i = 0; i < (сколько[н] || 0); i++) п.хозяева[простые[взято++]] = к; });
        п.раунд = п.всегоРаундов;
        п.завершена = true;
        п.конец = { причина: 'раунды', победитель: null, раунд: п.раунд };
        Object.assign(п, window.ЗахватПравила.итог(п));
        window.ЗахватЭкран.партияОкончена(п);
        return true;
      });
      проверить(собрано, 'итог: законченная партия передана экрану');
      await страница.waitForTimeout(500);
      const итог = await страница.evaluate(() => {
        const д = document.getElementById('захват-итог');
        const р = д ? д.getBoundingClientRect() : null;
        const хв = document.getElementById('захват-похвастаться');
        return {
          открыт: !!д && д.open,
          заголовок: (document.getElementById('захват-итог-заголовок').textContent || '').trim(),
          строк: document.querySelectorAll('#захват-итог-места .захват-итог-строка').length,
          плюсов: document.querySelectorAll('#захват-итог-места .захват-итог-плюс').length,
          влезает: !!р && р.left >= 0 && р.right <= window.innerWidth,
          хвастатьВидно: !!хв && getComputedStyle(хв).display !== 'none',
          сохранение: localStorage.getItem('zahvat-save')
        };
      });
      проверить(итог.открыт && итог.заголовок === '2-е место — в плюсе', 'итог: окно открыто, H1 «' + итог.заголовок + '»');
      проверить(итог.строк === 4 && итог.плюсов === 2, 'итог: строк мест ' + итог.строк + ' из 4, «в плюсе» у ' + итог.плюсов + ' из 2');
      проверить(итог.влезает, 'итог: окно целиком по ширине экрана');
      проверить(итог.хвастатьВидно, 'итог: «Похвастаться» видна (2-е место — в плюсе)');
      проверить(итог.сохранение === null, 'итог: zahvat-save очищен');
      await без_прокрутки('итог');
      await снять('8-итог');

      // 7. Лист «Вы сдались»: «Ещё партия» из итога, потом сдача в раунде 1.
      await страница.click('#захват-ещё-партия');
      await страница.waitForTimeout(600);
      await страница.evaluate(() => window.ЗахватЭкран.сдатьсяВПартии());
      await страница.waitForTimeout(500);
      const лист = await страница.evaluate(() => {
        const л = document.getElementById('захват-выбыл');
        const р = л ? л.getBoundingClientRect() : null;
        return {
          виден: !!л && !л.classList.contains('скрыт') && !!р && р.height > 0,
          заголовок: (document.getElementById('захват-выбыл-заголовок').textContent || '').trim(),
          влезает: !!р && р.left >= 0 && р.right <= window.innerWidth
        };
      });
      проверить(лист.виден && /^Вы сдались в раунде 1 · [0-9]-е место$/.test(лист.заголовок), 'лист: виден, «' + лист.заголовок + '»');
      проверить(лист.влезает, 'лист: целиком по ширине экрана');
      await без_прокрутки('лист «Вы сдались»');
      await снять('9-лист-вы-сдались');

      // Консоль
      проверить(ошибки.length === 0, 'консоль без ошибок' + (ошибки.length ? ': ' + ошибки.join(' | ') : ''));
      проверить(сбои.length === 0, 'нет 404 и неудавшихся запросов' + (сбои.length ? ': ' + сбои.join(' | ') : ''));
      await контекст.close();
    }
    // Подсказки первой партии (В8в): чистая память, свой контекст на каждой ширине.
    for (const [ш, в] of [[320, 568], [390, 844]]) await проверитьСоветы(браузер, порт, ш, в);
  } finally {
    await браузер.close();
    сервер.close();
  }
  console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);
  console.log('Снимки: ' + ПАПКА_СНИМКОВ);
  process.exit(провалов ? 1 : 0);
}

