/* Сервер: сперва ищет файл в папке-копии (если дана), потом в проекте. */
function поднятьСервер(копия) {
  const сервер = http.createServer((запрос, ответ) => {
    let путь = '/';
    try { путь = decodeURIComponent(запрос.url.split('?')[0]); } catch (_) { /* как есть */ }
    if (путь === '/') путь = '/index.html';
    const варианты = [];
    if (копия) варианты.push(path.join(копия, путь));
    варианты.push(path.join(ПРОЕКТ, путь));
    for (const файл of варианты) {
      if (!файл.startsWith(копия && файл.startsWith(копия) ? копия : ПРОЕКТ)) continue;
      try {
        if (fs.statSync(файл).isFile()) {
          ответ.writeHead(200, { 'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'application/octet-stream' });
          ответ.end(fs.readFileSync(файл));
          return;
        }
      } catch (_) { /* пробуем дальше */ }
    }
    ответ.writeHead(404); ответ.end('нет такого файла');
  });
  return new Promise(готово => сервер.listen(0, '127.0.0.1', () => готово(сервер)));
}

/* Копия во временной папке. Что портим:
   - css: подключение style-захват.css заменено на несуществующий файл (красным должна стать проверка 404);
   - полоса: в копии js/захват-экран.js наполнение нижней полосы не вызывается (красным — пункт про три вкладки). */
function подготовитьКопию(портитьCss, портитьПолосу, портитьСовет) {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-сломан-'));
  if (портитьCss) {
    const html = fs.readFileSync(path.join(ПРОЕКТ, 'захват.html'), 'utf8');
    const испорчен = html.replace('style-захват.css', 'style-захват-НЕТ-ТАКОГО.css');
    if (испорчен === html) throw new Error('--сломать: в захват.html не нашлось подключения style-захват.css');
    fs.writeFileSync(path.join(папка, 'захват.html'), испорчен);
  }
  if (портитьПолосу || портитьСовет) {
    let исходник = fs.readFileSync(path.join(ПРОЕКТ, 'js', 'захват-экран.js'), 'utf8');
    if (портитьПолосу) {
      const начало = 'function наполнитьНижнююПолосу() {';
      if (исходник.indexOf(начало) === -1) throw new Error('--сломать: в js/захват-экран.js не нашлась функция наполнитьНижнююПолосу');
      // Функция сразу выходит: полоса остаётся пустой.
      исходник = исходник.replace(начало, начало + ' return;');
    }
    if (портитьСовет) {
      // Узел подсказок первой партии: освежитьСовет() у партии с ботами (у сети — показатьПилюлю с «!текст», его не трогаем).
      const показ = "$('захват-совет').classList.toggle('скрыт', !совет);";
      if (исходник.split(показ).length !== 2) throw new Error('--сломать-совет: в js/захват-экран.js не нашёлся показ пилюли-подсказки');
      // Пилюля всегда спрятана: краснеть должны проверки подсказок первой партии.
      исходник = исходник.replace(показ, "$('захват-совет').classList.add('скрыт');");
    }
    fs.mkdirSync(path.join(папка, 'js'), { recursive: true });
    fs.writeFileSync(path.join(папка, 'js', 'захват-экран.js'), исходник);
  }
  return папка;
}

