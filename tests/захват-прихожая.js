'use strict';

/* =====================================================================
   ПРИХОЖАЯ «ЗАХВАТА» (Б16): гости видят, сколько раундов выбрал хозяин.

   Две половины пути поля раундовЗахвата:
     А) сервер: server/партия-по-сети.js, видДляИгрока — поле обёртки
        раундовЗахвата обязано дойти до гостя (список ПОЛЯ_ОБЁРТКИ_ДЛЯ_ИГРОКА);
     Б) экран: общее/js/дурак-комната.js, строка правил стола — «Захват · 20 раундов»,
        поля нет — «Захват · 15 раундов»; дурак и шахматы — прежние строки.
   Без сети и браузера: сервер — require копии файла, экран — поддельный
   документ (tests/поддельный-браузер.js), как в tests/комната-подпись-игры.js.

   Запуск:
       node tests/захват-прихожая.js
   Ломающий запуск (портит КОПИИ во временной папке ОС, файлы проекта не трогает;
   в каждой порче место найдено ровно один раз, иначе провал):
       node tests/захват-прихожая.js --сломать
   Вызывает сам себя на копиях и требует, чтобы каждая порча покраснела.
   Служебные доводы для такого вызова: --сервер=<путь> --комната=<путь>.
   Выход 0 — провалов нет, 1 — есть.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');
const { поднять, сделатьДокумент } = require('./поддельный-браузер.js');

const КОРЕНЬ = path.join(__dirname, '..');
const НАСТОЯЩИЙ_СЕРВЕР = path.join(КОРЕНЬ, 'server', 'партия-по-сети.js');
const НАСТОЯЩАЯ_КОМНАТА = path.join(КОРЕНЬ, 'общее', 'js', 'дурак-комната.js');

function довод(имя) {
  const найден = process.argv.find(function (д) { return д.indexOf('--' + имя + '=') === 0; });
  return найден ? найден.slice(имя.length + 3) : '';
}

const проверки = [];
function проверить(условие, текст) {
  проверки.push({ ок: Boolean(условие), текст: текст });
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + текст);
}

/* ---------------------------------------------------------------------
   А. Сервер: поле доходит до гостя
   --------------------------------------------------------------------- */
function проверитьСервер(путьСервера) {
  console.log('\n=== А. Сервер: видДляИгрока переносит раундовЗахвата (' + путьСервера + ') ===');
  const сеть = require(путьСервера);
  const партия = сеть.начатьПартию(null, { игроки: [сеть.ПЕРВЫЙ, сеть.ВТОРОЙ] });
  if (!партия) throw new Error('партия не раздалась — проверка сломана');

  for (const раундов of [20, 10]) {
    const вид = сеть.видДляИгрока(партия, сеть.ПЕРВЫЙ, { код: 'TEST', игра: 'захват', раундовЗахвата: раундов });
    проверить(Boolean(вид) && вид.раундовЗахвата === раундов,
      'обёртка с раундовЗахвата: ' + раундов + ' — гость получил ' + (вид ? JSON.stringify(вид.раундовЗахвата) : 'нет вида'));
  }
  const без = сеть.видДляИгрока(партия, сеть.ПЕРВЫЙ, { код: 'TEST', игра: 'захват' });
  проверить(Boolean(без) && !('раундовЗахвата' in без), 'обёртка без поля — у гостя поля тоже нет (пустых полей не заводим)');
}

/* ---------------------------------------------------------------------
   Б. Экран: строка правил в поддельном документе
   --------------------------------------------------------------------- */
function видКомнаты(добавки) {
  return Object.assign({
    игра: 'дурак', этап: 'ожидание', мест: 2, мойНомер: 2, яХозяин: false,
    можноНачать: false, переводной: false, парами: false, открытыйСтол: true,
    застолом: [{ номер: 1, этоЯ: false, имя: 'Аня', хозяин: true, наСвязи: true }]
  }, добавки || {});
}

function узлыШапкиИзРазметки() {
  const разметка = fs.readFileSync(path.join(КОРЕНЬ, 'index.html'), 'utf8');
  const строка = разметка.match(/<span id="(комната-режим)" class="[^"]*"><\/span>\s*<p id="(комната-правила)" class="[^"]*"><\/p>/);
  if (!строка) throw new Error('в index.html не нашёл узлы шапки комнаты — проверка устарела');
  return { режим: строка[1], правила: строка[2] };
}

function строкаПравил(исходник, ид, вид) {
  const документ = сделатьДокумент();
  const корень = документ.узел('div', { id: 'комната' });
  const режим = документ.узел('span', { id: ид.режим, класс: 'путь__режим путь__режим--друзья' });
  const правила = документ.узел('p', { id: ид.правила, класс: 'комната__правила' });
  корень.appendChild(режим);
  корень.appendChild(правила);
  документ.body.appendChild(корень);
  const рез = поднять(исходник, { документ: документ, имяФайла: 'общее/js/дурак-комната.js' });
  рез.окно.ДуракКомната.показать(видКомнаты(вид), {});
  const текст = правила.textContent;
  рез.окно.ДуракКомната.спрятать();
  return текст;
}

function проверитьЭкран(путьКомнаты) {
  console.log('\n=== Б. Экран: строка правил стола (' + путьКомнаты + ') ===');
  const исходник = fs.readFileSync(путьКомнаты, 'utf8');
  const ид = узлыШапкиИзРазметки();
  const случаи = [
    { имя: 'захват, 20 раундов', вид: { игра: 'захват', раундовЗахвата: 20 }, ждём: 'Захват · 20 раундов' },
    { имя: 'захват, 10 раундов', вид: { игра: 'захват', раундовЗахвата: 10 }, ждём: 'Захват · 10 раундов' },
    { имя: 'захват, поля нет — по умолчанию', вид: { игра: 'захват' }, ждём: 'Захват · 15 раундов' },
    { имя: 'шахматы с контролем (прежняя строка)', вид: { игра: 'шахматы', контрольШахмат: 'блиц 5+3' }, ждём: 'Шахматы · блиц 5+3' },
    { имя: 'шахматы без контроля (прежняя строка)', вид: { игра: 'шахматы' }, ждём: 'Шахматы' },
    { имя: 'дурак (прежняя строка)', вид: { игра: 'дурак' }, ждём: 'Подкидной' },
    { имя: 'у шахмат лишнее поле раундовЗахвата не мешает', вид: { игра: 'шахматы', раундовЗахвата: 20 }, ждём: 'Шахматы' }
  ];
  for (const с of случаи) {
    const есть = строкаПравил(исходник, ид, с.вид);
    проверить(есть === с.ждём, с.имя + ': «' + с.ждём + '» (получили «' + есть + '»)');
  }
}

/* ---------------------------------------------------------------------
   Ломающий запуск
   --------------------------------------------------------------------- */
function порча(текст, что, наЧто, файл) {
  const части = текст.split(что);
  if (части.length !== 2) {
    throw new Error('в ' + файл + ' место «' + что + '» найдено ' + (части.length - 1) + ' раз(а), нужно ровно один — порча устарела');
  }
  return части.join(наЧто);
}

function прогнатьКопию(доводы) {
  const р = spawnSync(process.execPath, [__filename].concat(доводы), { encoding: 'utf8' });
  return р.status;
}

function сломать() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-прихожая-сломать-'));
  let поломок = 0;
  let покраснело = 0;
  try {
    const сервер = fs.readFileSync(НАСТОЯЩИЙ_СЕРВЕР, 'utf8');
    const комната = fs.readFileSync(НАСТОЯЩАЯ_КОМНАТА, 'utf8');
    // В копии сервера относительный путь к правилам заменяем на настоящий, иначе копия из tmp не загрузится.
    const сАбсолютнымПутём = порча(сервер, "require('../игры/дурак/game.js')",
      'require(' + JSON.stringify(path.join(КОРЕНЬ, 'игры', 'дурак', 'game.js')) + ')', 'server/партия-по-сети.js');

    const порчи = [
      { имя: 'сервер без слова в списке полей', доводы: 'сервер',
        текст: порча(сАбсолютнымПутём, "'контрольШахмат', 'раундовЗахвата', ", "'контрольШахмат', ", 'server/партия-по-сети.js'),
        файл: 'сервер-сломан.js' },
      { имя: 'комната без ветки «захвата»', доводы: 'комната',
        текст: порча(комната, "if (игра === 'захват') {", "if (игра === 'захват-сломано') {", 'общее/js/дурак-комната.js'),
        файл: 'комната-без-ветки.js' },
      { имя: 'комната: 15 по умолчанию заменено на 12', доводы: 'комната',
        текст: порча(комната, 'вид.раундовЗахвата > 0 ? вид.раундовЗахвата : 15;', 'вид.раундовЗахвата > 0 ? вид.раундовЗахвата : 12;', 'общее/js/дурак-комната.js'),
        файл: 'комната-12.js' }
    ];

    // Целая копия сервера нужна рядом с копией комнаты: комната require'ит ./игры-реестр.js.
    fs.copyFileSync(path.join(КОРЕНЬ, 'общее', 'js', 'игры-реестр.js'), path.join(папка, 'игры-реестр.js'));

    for (const п of порчи) {
      поломок++;
      const путь = path.join(папка, п.файл);
      fs.writeFileSync(путь, п.текст, 'utf8');
      const код = прогнатьКопию(['--' + п.доводы + '=' + путь, '--тихо']);
      const красная = код === 1;
      if (красная) покраснело++;
      console.log((красная ? '  покраснела — ' : '  НЕ ПОКРАСНЕЛА — ') + п.имя + ' (код выхода ' + код + ')');
    }
  } catch (сбой) {
    console.log('  ПЛОХО — порча не приготовилась: ' + (сбой && сбой.message));
  } finally {
    try { fs.rmSync(папка, { recursive: true, force: true }); } catch (_) { /* не страшно */ }
  }
  console.log('\nПоломок: ' + поломок + ', покраснело: ' + покраснело);
  process.exit(поломок > 0 && поломок === покраснело ? 0 : 1);
}

/* ---------------------------------------------------------------------
   Главное
   --------------------------------------------------------------------- */
function главное() {
  if (process.argv.indexOf('--сломать') !== -1) return сломать();
  const путьСервера = довод('сервер') || НАСТОЯЩИЙ_СЕРВЕР;
  const путьКомнаты = довод('комната') || НАСТОЯЩАЯ_КОМНАТА;
  try {
    проверитьСервер(путьСервера);
    проверитьЭкран(путьКомнаты);
  } catch (сбой) {
    проверить(false, 'проверка упала — ' + (сбой && сбой.stack || сбой));
  }
  const провалы = проверки.filter(function (п) { return !п.ок; });
  console.log('\nИтого проверок: ' + проверки.length + ', провалов: ' + провалы.length);
  process.exit(провалы.length || проверки.length === 0 ? 1 : 0);
}

главное();
