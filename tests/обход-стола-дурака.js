/* Поломки проверяются ПО ОТДЕЛЬНОСТИ, не разом: если применить обе сразу,
   поломка «а» уводит все карты руки на 3000px вправо, и там, где стоят
   кнопки «Беру»/«Бито», физически не остаётся ни одной карты — поломке «б»
   попросту нечем их закрыть, и находка не срабатывает (проверено прогоном:
   вместе обе поломки давали только «а», «б» тонула). Поэтому ломающий
   прогон устраивает два отдельных коротких захода на состоянии
   «начало-партии» — один на поломку «а», другой на «б». */
function создатьИспорченныйStyleCss(какая) {
  const оригинал = fs.readFileSync(ПУТЬ_СТИЛЯ, 'utf8');
  if (какая === 'а') {
    const маркерА = '#приложение #экран-игры #рука-человека {';
    if (оригинал.indexOf(маркерА) === -1) {
      throw new Error('Поломка «а»: в style.css не нашёлся селектор «' + маркерА + '» — ' +
        'похоже, полоску руки человека переименовали, поломку нужно поправить вслед за ней.');
    }
    return оригинал +
      '\n/* --- ломающий прогон tests/обход-стола-дурака.js, поломка «а» --- */\n' +
      // контейнер карт руки — задираем left, right:0 у него больше не властен (.веер — position:absolute; inset:0).
      '#карты-человека.веер {\n  left: 3000px !important;\n  right: auto !important;\n}\n';
  }
  const маркерБ = '#панель-кнопок > #кнопка-беру';
  if (оригинал.indexOf(маркерБ) === -1) {
    throw new Error('Поломка «б»: в style.css не нашёлся селектор «' + маркерБ + '» — ' +
      'похоже, кнопку «Беру» переименовали, поломку нужно поправить вслед за ней.');
  }
  return оригинал +
    '\n/* --- ломающий прогон tests/обход-стола-дурака.js, поломка «б» --- */\n' +
    // полоска руки поднята над кнопками и подтянута к ним — кнопки «Беру»/«Бито» под картами.
    '#рука-человека {\n  position: relative !important;\n  z-index: 50 !important;\n  margin-bottom: -60px !important;\n}\n';
}

