/** Автоигрок крутится в фоне, свой опрос каждые 60мс ловит условие и сразу его глушит. */
async function довестиАвтоигрокомДоУсловия(страница, условие, таймаутMs) {
  await впрыснутьПомощников(страница);
  await страница.evaluate(() => window.УскорительПауз.включить());
  await страница.evaluate(() => window.Автоигрок.начать(0, false, 0));
  const начало = Date.now();
  let достигнуто = false;
  while (Date.now() - начало < таймаутMs) {
    достигнуто = await страница.evaluate(условие).catch(() => false);
    if (достигнуто) break;
    await страница.waitForTimeout(60);
  }
  await страница.evaluate(() => { if (window.Автоигрок && window.Автоигрок.работает()) window.Автоигрок.стоп(); }).catch(() => null);
  await страница.evaluate(() => { if (window.УскорительПауз) window.УскорительПауз.выключить(); }).catch(() => null);
  return достигнуто;
}

