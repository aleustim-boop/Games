/**
 * Сценарий 5 целиком: открыть доску вдвоём, зайти в правила через лист
 * (в Telegram — пункт «Настройки»), закрыть их стрелкой Telegram, вторым
 * нажатием стрелки словить вопрос «Завершить партию?» (партия ведь ещё
 * идёт), подтвердить кнопкой «Завершить» в плашке и третьим нажатием
 * стрелки уйти с меню «с кем играть» на витрину игр.
 * Общая функция для основного прогона и для ломающего запуска — читает
 * ровно то же устройство (id «плашка-завершить», класс кнопки
 * «.плашка-завершить__да»), что рисует js/лист-ещё.js.
 */
async function прогонСценария5(страница, метка) {
  await страница.click('#лобби-вдвоём');       // до кнопки «Как играть» надо дойти через доску
  await страница.waitForTimeout(300);
  /* В телеграм-режиме строку «‹ ⋯» рисует сам Telegram — наша
     «#кнопка-игра-ещё» спрятана правилом «html.в-телеграме .верх-игры
     {display:none}», и клик по ней виснет (элемент невидим). Лист
     открывается пунктом «Настройки» в меню Telegram — так же, как
     у шахмат (см. tests/шахматы-первый-взгляд.js, сценарий 4). */
  await страница.evaluate(() => window.ПоддельныйТелеграм.нажатьНастройки());
  await страница.waitForTimeout(250);
  await страница.click('#кнопка-лист-игры-правила');
  проверить(await страница.evaluate(() => window.ШашкиКакИграть.открыты()), метка + ': правила открыты');
  await страница.evaluate(() => window.ПоддельныйТелеграм.нажатьНазад());
  await страница.waitForTimeout(200);
  проверить(await страница.evaluate(() => !window.ШашкиКакИграть.открыты() &&
    document.getElementById('экран-шашек').classList.contains('экран--виден')),
    метка + ': первое нажатие стрелки закрыло правила, доска на месте');

  /* Партия вдвоём идёт на столе — второе нажатие не бросает её молча,
     а открывает ту же общую плашку подтверждения, что и строка листа
     «Завершить партию» и «‹» на столе (штаб/план-выход-из-партии.md, Э4).
     На доску при этом не возвращаемся и в меню «с кем играть» не уходим —
     ждём решения человека. */
  await страница.evaluate(() => window.ПоддельныйТелеграм.нажатьНазад());
  await страница.waitForTimeout(300);
  const послеВторого = await страница.evaluate(() => {
    const плашка = document.getElementById('плашка-завершить');
    return {
      плашкаОткрыта: Boolean(плашка && !плашка.classList.contains('скрыт')),
      доскаВидна: document.getElementById('экран-шашек').classList.contains('экран--виден'),
      режимыОткрыты: Boolean(window.ШашкиРежимы && window.ШашкиРежимы.открыты())
    };
  });
  проверить(послеВторого.плашкаОткрыта && послеВторого.доскаВидна && !послеВторого.режимыОткрыты,
    метка + ': второе нажатие открыло вопрос «Завершить партию?», доска ещё видна, в меню «с кем играть» не ушли ' +
    '(' + JSON.stringify(послеВторого) + ')');

  /* Подтверждаем кнопкой «Завершить» в самой плашке — стрелка Telegram
     тут больше ни при чём, это обычный тап по экрану. Кнопки может не
     быть вовсе (если что-то сломалось выше) — тогда просто идём дальше
     с пустыми руками, а не роняем весь прогон. */
  const кнопкаДа = await страница.$('.плашка-завершить__да');
  if (кнопкаДа) await кнопкаДа.click();
  await страница.waitForTimeout(300);
  const послеПодтверждения = await страница.evaluate(() => {
    const плашка = document.getElementById('плашка-завершить');
    return {
      плашкаЗакрыта: !плашка || плашка.classList.contains('скрыт'),
      режимыОткрыты: Boolean(window.ШашкиРежимы && window.ШашкиРежимы.открыты())
    };
  });
  проверить(Boolean(кнопкаДа) && послеПодтверждения.плашкаЗакрыта && послеПодтверждения.режимыОткрыты,
    метка + ': кнопка «Завершить» в плашке нашлась, закрыла её и увела на экран «с кем играть» ' +
    '(' + JSON.stringify(послеПодтверждения) + ')');

  /* Дальше стрелка снова просто отматывает по одному шагу: из меню — на витрину. */
  await страница.evaluate(() => window.ПоддельныйТелеграм.нажатьНазад());
  await страница.waitForTimeout(500);
  проверить(/index\.html$/.test(страница.url()), метка + ': третье нажатие увело на index.html: ' + страница.url());
}

