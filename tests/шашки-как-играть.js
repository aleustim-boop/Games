const ТИПЫ_ФАЙЛОВ = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.svg': 'image/svg+xml'
};

function подготовитьСломаннуюКопию() {
  const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'шашки-как-играть-'));
  fs.copyFileSync(path.join(КОРЕНЬ, 'шашки.html'), path.join(врем, 'шашки.html'));
  for (const имя of ['style.css', 'style-коллекция.css', 'style-шашки.css']) {
    fs.copyFileSync(path.join(КОРЕНЬ, имя), path.join(врем, имя));
  }
  fs.cpSync(path.join(КОРЕНЬ, 'js'), path.join(врем, 'js'), { recursive: true });
  fs.cpSync(path.join(КОРЕНЬ, 'img', 'шашки'), path.join(врем, 'img', 'шашки'), { recursive: true });

  const путьЭкрана = path.join(врем, 'js', 'шашки-экран.js');
  const исходник = fs.readFileSync(путьЭкрана, 'utf8');
  const строка = "return Boolean(листЕщё && typeof листЕщё.спроситьЗавершить === 'function' && листЕщё.спроситьЗавершить());";
  if (исходник.indexOf(строка) === -1) {
    console.log('ОШИБКА: в копии js/шашки-экран.js не нашлась строка «' + строка + '» —');
    console.log('приём порчи устарел (спроситьЗавершить переписали), этот тест надо обновить.');
    process.exit(1);
  }
  fs.writeFileSync(путьЭкрана,
    исходник.split(строка).join("return false; /* порчено --сломать: вопрос «Завершить партию?» отключён */"),
    'utf8');
  return врем;
}

function поднятьРаздачу(корень) {
  const сервер = http.createServer(function (запрос, ответ) {
    let путь = запрос.url.split('?')[0].split('#')[0];
    try { путь = decodeURIComponent(путь); } catch (ошибка) { /* оставим как есть */ }
    const файл = path.join(корень, путь === '/' ? 'шашки.html' : путь.slice(1));
    if (файл.indexOf(корень) !== 0) { ответ.writeHead(403); ответ.end('нельзя'); return; }
    fs.readFile(файл, function (беда, тело) {
      if (беда) { ответ.writeHead(404); ответ.end('нет такого файла'); return; }
      ответ.writeHead(200, { 'Content-Type': ТИПЫ_ФАЙЛОВ[path.extname(файл).toLowerCase()] || 'text/plain' });
      ответ.end(тело);
    });
  });
  return new Promise((готово) => сервер.listen(0, '127.0.0.1', () => готово(сервер)));
}
