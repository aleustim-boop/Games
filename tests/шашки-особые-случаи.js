/* =====================================================================
   Особые случаи страницы шашек:
     1) Telegram старой версии — своей стрелки «Назад» нет,
        значит кнопка на странице обязана остаться;
     2) js/telegram.js не доехал — игра всё равно должна поздороваться
        с Telegram сама, не падать и понятно объяснить про рекорды;
     3) сколько высоты отняли у доски две новые кнопки.
   ===================================================================== */

const { chromium, подготовитьПодделку } = require('./браузер-робот.js');
const ПОРТ = Number(process.argv[2]) || 8080;    // страничный сервер уже поднят
const АДРЕС = 'http://127.0.0.1:' + ПОРТ + '/шашки.html';

let провалов = 0;
function проверить(условие, слова) {
  console.log((условие ? '  ок   — ' : '  ПЛОХО— ') + слова);
  if (!условие) провалов++;
}

/* Подделка Telegram — общая (tests/поддельный-телеграм.js); версию ей
   называем настройкой. Стрелка у подделки есть, но старый Telegram (6.0)
   отвечает «нет» на вопрос про версию, и игра её трогать не должна. */

(async () => {
  const браузер = await chromium.launch();

  /* ---- 1. Telegram, который стрелку «Назад» не умеет ---- */
  console.log('\n=== 1. Telegram старой версии (6.0) ===');
  {
    const окно = await браузер.newContext({ viewport: { width: 360, height: 640 } });
    const страница = await окно.newPage();
    await подготовитьПодделку(страница, { версия: '6.0', стрелка: true });
    await страница.goto(АДРЕС);
    await страница.waitForTimeout(300);
    const что = await страница.evaluate(() => ({
      ready: window.__дневник.ready,
      expand: window.__дневник.expand,
      стрелка: window.__дневник.стрелка,
      кнопкаСкрыта: document.getElementById('кнопка-назад').classList.contains('скрыт')
    }));
    проверить(что.ready === 1 && что.expand === 1, 'окно всё равно раскрыто (ready/expand): ' + что.ready + '/' + что.expand);
    проверить(что.стрелка === 0, 'системную стрелку не трогали — эта версия её не умеет');
    проверить(!что.кнопкаСкрыта, 'своя кнопка «Назад» осталась на странице');
    await окно.close();
  }

  /* ---- 2. js/telegram.js не доехал ---- */
  console.log('\n=== 2. Хранилище не подключилось (js/telegram.js заблокирован) ===');
  {
    const окно = await браузер.newContext({ viewport: { width: 360, height: 640 } });
    const страница = await окно.newPage();
    const исключения = [];
    страница.on('pageerror', (о) => исключения.push(о.message));
    await подготовитьПодделку(страница, { версия: '7.0', стрелка: true });
    await страница.route('**/js/telegram.js*', (п) => п.abort());
    await страница.goto(АДРЕС);
    await страница.waitForTimeout(400);

    const что = await страница.evaluate(async () => {
      const подпись = await window.ШашкиРекорды.записатьПартию({ исход: 'победа', уровень: 'лёгкий' });
      window.ШашкиРекорды.показать();
      return {
        ready: window.__дневник.ready,
        expand: window.__дневник.expand,
        подпись: подпись,
        рейтингЕсть: !!window.Рейтинг,
        доска: document.querySelectorAll('#доска .поле').length
      };
    });
    await страница.waitForTimeout(200);
    const слова = await страница.evaluate(() =>
      document.querySelector('#таблица-рекордов .таблица__пусто').textContent);

    проверить(!что.рейтингЕсть, 'хранилища и правда нет (window.Рейтинг не создан)');
    проверить(что.ready === 1 && что.expand === 1, 'шашки поздоровались с Telegram сами: ' + что.ready + '/' + что.expand);
    проверить(что.доска === 64, 'доска всё равно построена: клеток ' + что.доска);
    проверить(/сохранить не удалось/.test(что.подпись),
      'победа посчитана, а про несохранение сказано прямо: «' + что.подпись + '»');
    console.log('  на экране рекордов: «' + слова + '»');
    проверить(/не подключилось/.test(слова), 'человеку объяснили, почему рекордов нет');
    проверить(исключения.length === 0, 'ни одного исключения' + (исключения.length ? ': ' + исключения.join(' | ') : ''));
    await окно.close();
  }

  /* ---- 3. Сколько высоты отняли новые кнопки ---- */
  console.log('\n=== 3. Цена двух новых кнопок для доски ===');
  for (const размер of [{ w: 320, h: 568 }, { w: 360, h: 640 }, { w: 390, h: 844 }]) {
    const окно = await браузер.newContext({ viewport: { width: размер.w, height: размер.h } });
    const страница = await окно.newPage();
    await страница.goto(АДРЕС);
    await страница.waitForTimeout(250);
    const мера = await страница.evaluate(() => {
      const доска = () => Math.round(document.getElementById('доска').getBoundingClientRect().width);
      const панель = () => Math.round(document.querySelector('.панель-доски').getBoundingClientRect().height);
      const было = { доска: доска(), панель: панель() };
      document.getElementById('кнопка-рекорды').style.display = 'none';
      document.getElementById('кнопка-назад').style.display = 'none';
      const стало = { доска: доска(), панель: панель() };
      return { сНовыми: было, безНовых: стало };
    });
    console.log('  ' + размер.w + '×' + размер.h +
      ': доска ' + мера.сНовыми.доска + ' (без новых кнопок было бы ' + мера.безНовых.доска + ')' +
      ', ряд кнопок ' + мера.сНовыми.панель + ' вместо ' + мера.безНовых.панель);
    проверить(мера.сНовыми.доска >= мера.безНовых.доска, 'доска от новых кнопок не уменьшилась');
    await окно.close();
  }

  await браузер.close();
  console.log('\n' + (провалов === 0 ? 'ВСЁ ЗЕЛЁНОЕ' : 'ПРОВАЛОВ: ' + провалов));
  process.exit(провалов === 0 ? 0 : 1);
})().catch((о) => { console.error('проверка сломалась:', о); process.exit(2); });
