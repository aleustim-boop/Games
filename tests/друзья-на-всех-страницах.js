'use strict';

/* =====================================================================
   ПОДКЛЮЧЕНИЕ js/друзья-экран.js НА ВСЕХ СТРАНИЦАХ С ПРОФИЛЕМ
   (задача Ф4 плана штаб/план-друзья-везде.md, проверка в node, БЕЗ браузера).

   Смысл. Экран «Друзья» теперь общий модуль: любая страница, у которой
   есть кнопка «Профиль» (js/профиль-экран.js), должна СРАЗУ следом
   подключать и js/друзья-экран.js — иначе кнопка «Друзья» в профиле
   тихо не появится (мёртвой она не бывает по правилу проекта, значит
   просто исчезнет с экрана — не крах, но обещанная кнопка пропала).

   Что проверяем на каждой *.html из корня проекта, где есть подключение
   js/профиль-экран.js:
     1) на той же странице есть подключение js/друзья-экран.js;
     2) друзья-экран.js подключён ПОСЛЕ профиль-экран.js (по порядку строк
        в файле) — план прямо требует «сразу после»;
     3) метка ?v= у js/профиль-экран.js одна и та же на ВСЕХ найденных
        страницах, и то же самое отдельно для ?v= у js/друзья-экран.js —
        разъезд номеров означает, что часть игроков получит из кэша
        разные версии одного и того же общего файла.
   Страниц без профиля (одиночные игры вроде 2048.html) проверка не
   касается вовсе — не их файл.

   Ноль найденных страниц с профилем — это ПРОВАЛ проверки (узел
   переименовали или файл профиля исчез), а не тихий пропуск.

   Запуск:
       node tests/друзья-на-всех-страницах.js
       node tests/друзья-на-всех-страницах.js --папка=<копия страниц>
                                    (свою копию папки с html даёт вызывающий)

   Ломающий запуск (портит КОПИЮ во временной папке — ни один файл
   проекта не трогается):
       node tests/друзья-на-всех-страницах.js --сломать
   Копирует все *.html корня во временную папку и вырезает в НЕЙ, в
   нарды.html, строку подключения js/друзья-экран.js — проверка обязана
   покраснеть на пункте «друзья-экран.js подключён».
   Выход 0 — провалов нет (при --сломать это как раз ПЛОХО, см. ниже),
   1 — провалы есть.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');

const доводПапки = process.argv.find(function (д) { return д.indexOf('--папка=') === 0; });
const СЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;

let ПАПКА = доводПапки ? доводПапки.split('=')[1] : КОРЕНЬ;
let временнаяПапка = null;

if (доводПапки && !fs.existsSync(ПАПКА)) {
  console.error('довод --папка=' + ПАПКА + ': такой папки нет');
  process.exit(2);
}

/* --------------------------------------------------------------------
   Ломающий запуск: своя копия во временной папке, порченная НАРОЧНО.
   -------------------------------------------------------------------- */
if (СЛОМАТЬ) {
  if (доводПапки) {
    console.error('--сломать и --папка= вместе не имеют смысла: --сломать сам строит свою копию.');
    process.exit(2);
  }
  временнаяПапка = fs.mkdtempSync(path.join(os.tmpdir(), 'друзья-везде-сломать-'));
  const файлыКорня = fs.readdirSync(КОРЕНЬ).filter(function (и) { return и.toLowerCase().endsWith('.html'); });
  let вырезано = false;
  файлыКорня.forEach(function (имя) {
    let текст = fs.readFileSync(path.join(КОРЕНЬ, имя), 'utf8');
    if (имя === 'нарды.html') {
      const было = текст;
      // Вырезаем ровно тег подключения друзья-экран.js, каким бы ни было
      // число после ?v= — тот же приём, что и у боевой строки.
      текст = текст.replace(/<script src="js\/друзья-экран\.js\?v=[^"]*"><\/script>\s*/, '');
      вырезано = (текст !== было);
    }
    fs.writeFileSync(path.join(временнаяПапка, имя), текст, 'utf8');
  });
  if (!вырезано) {
    console.error('ОШИБКА порчи --сломать: строка подключения js/друзья-экран.js в нарды.html не нашлась — приём порчи устарел.');
    process.exit(2);
  }
  ПАПКА = временнаяПапка;
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: копия страниц в ' + временнаяПапка + ', в нарды.html вырезана строка ' +
    'подключения js/друзья-экран.js — проверка обязана покраснеть ***');
  console.log('');
}

let всего = 0;
let провалов = 0;
function проверить(условие, слова) {
  всего++;
  if (условие) console.log('  ок    — ' + слова);
  else { провалов++; console.log('  ПЛОХО — ' + слова); }
}
function сказать(слова) { console.log(слова); }

/** Найти в тексте страницы подключение вида src="js/ИМЯ.js?v=ЧИСЛО-ИЛИ-СЛОВО".
 *  Возвращает { версия, позиция } (позиция — индекс совпадения в тексте,
 *  чтобы сравнить «кто раньше») или null, если такого тега нет вовсе. */
function найтиПодключение(текст, имяФайла) {
  const экранировано = имяФайла.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const рег = new RegExp('src="js/' + экранировано + '\\?v=([^"]+)"');
  const м = рег.exec(текст);
  if (!м) return null;
  return { версия: м[1], позиция: м.index };
}

const страницы = fs.readdirSync(ПАПКА).filter(function (и) { return и.toLowerCase().endsWith('.html'); });
сказать('Папка страниц: ' + ПАПКА + ' (html-файлов: ' + страницы.length + ')');
сказать('');

let найденоСПрофилем = 0;
const версииПрофиля = new Map();   // версия -> [файлы]
const версииДрузей = new Map();

страницы.sort().forEach(function (файл) {
  const текст = fs.readFileSync(path.join(ПАПКА, файл), 'utf8');
  const профиль = найтиПодключение(текст, 'профиль-экран.js');
  if (!профиль) return;   // страница вне зоны действия (одиночная игра без профиля)

  найденоСПрофилем++;
  console.log('=== ' + файл + ' ===');

  const друзья = найтиПодключение(текст, 'друзья-экран.js');
  проверить(Boolean(друзья), файл + ': на странице подключён js/друзья-экран.js');

  if (друзья) {
    проверить(друзья.позиция > профиль.позиция,
      файл + ': js/друзья-экран.js подключён ПОСЛЕ js/профиль-экран.js (позиции ' +
      профиль.позиция + ' → ' + друзья.позиция + ')');
    if (!версииДрузей.has(друзья.версия)) версииДрузей.set(друзья.версия, []);
    версииДрузей.get(друзья.версия).push(файл);
  }

  if (!версииПрофиля.has(профиль.версия)) версииПрофиля.set(профиль.версия, []);
  версииПрофиля.get(профиль.версия).push(файл);
});

console.log('');
console.log('=== Итоговые сводки ===');
проверить(найденоСПрофилем > 0,
  'нашлась хотя бы одна страница с js/профиль-экран.js (нашлось: ' + найденоСПрофилем + ')');

function сводкаРазъезда(имяФайла, карта) {
  const все = Array.from(карта.keys());
  if (все.length <= 1) {
    проверить(true, 'версия ?v= у js/' + имяФайла + ' одна и та же на всех страницах: ' +
      (все[0] === undefined ? '(страниц не было)' : '?v=' + все[0]));
    return;
  }
  const слова = все.map(function (в) { return 'v=' + в + ' у [' + карта.get(в).join(', ') + ']'; }).join('; ');
  проверить(false, 'версия ?v= у js/' + имяФайла + ' РАЗЪЕХАЛАСЬ между страницами: ' + слова);
}
сводкаРазъезда('профиль-экран.js', версииПрофиля);
сводкаРазъезда('друзья-экран.js', версииДрузей);

console.log('');
console.log('Итого проверок: ' + всего + ', провалов: ' + провалов);

if (временнаяПапка) {
  try { fs.rmSync(временнаяПапка, { recursive: true, force: true }); } catch (сбой) { /* не критично */ }
}

if (СЛОМАТЬ) {
  if (провалов === 0) {
    console.log('ПЛОХО: ломающий запуск не покраснел — проверка ничего не стережёт.');
    process.exit(1);
  }
  console.log('Ломающий запуск покраснел, как и должен.');
  process.exit(0);
}

process.exit(провалов ? 1 : 0);
