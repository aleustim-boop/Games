/* =====================================================================
   ШАХМАТЫ: «В МЕНЮ» С ДОСКИ НА ЛОББИ ПРЯЧЕТ ЛЮБОЙ ОТКРЫТЫЙ ЭКРАН.

   Беда (ревьюер профиля, 23.09 00:29). «уйтиНаВитрину()» в
   js/шахматы-экран.js, уходя с доски в лобби, снимала класс
   «экран--виден» только с перечисленных по именам узлов («экран-шахмат»,
   «экранПравил»). Общие экраны, которых на момент написания этой ветки
   ещё не было — рейтинг (js/рейтинг-экран.js) и профиль
   (js/профиль-экран.js, «экран-профиля-игрока») — открытые прямо с доски
   (например, через нижнюю полосу), оставались с классом «экран--виден»
   поверх лобби. Правка: список по именам заменён на широкий приём —
   снимаем «экран--виден» со ВСЕХ «.экран» (тем же селектором, каким
   рейтинг и профиль сами показывают себя), а уже потом показываем лобби.

   ЧТО ПРОВЕРЯЕТ ЭТОТ ФАЙЛ. Поднимает НАСТОЯЩИЙ js/шахматы-экран.js
   в песочнице vm с поддельным DOM (приём — как в
   tests/дверь-профиля-дурака.js: classList настоящий, через Set,
   document.querySelectorAll('.экран') и вправду находит узлы). Правила
   хода (js/шахматы-правила.js) берутся НАСТОЯЩИЕ через require —
   без них файл на первой же строке сам себя останавливает
   («Правила не загрузились»), и до «уйтиНаВитрину» дело не доходит.

     а) лобби скрыто, доска видна, поверх всего — посторонний
        «экран-профиля-игрока» с классом «экран--виден» (как будто
        профиль открыли прямо с доски). Клик по «кнопка-назад» (её
        слушает «уйтиНаВитрину» — своей двери наружу этот файл не отдаёт,
        см. `if (кнопкаНазад) кнопкаНазад.addEventListener('click', …)`)
        обязан спрятать посторонний экран и показать лобби.
     б) лобби уже открыто (класс «экран--виден» стоит на нём) — та же
        кнопка ведёт не в лобби, а на витрину: условие входа в широкую
        ветку (`!экранЛобби.classList.contains('экран--виден')`) должно
        остаться прежним. Посторонний экран эта ветка вовсе не трогает —
        широкий цикл прячущий «.экран» стоит только в ветке «а)».

   НАХОДКА ПРО ВЛОЖЕННОСТЬ ЭКРАНОВ (для отчёта штабу): в шахматы.html все
   узлы с классом «экран» (лобби, шахмат, итога, превращения, ничьей,
   рекордов, правил) — прямые дети #приложение, ни один не вложен внутрь
   другого. Общие экраны рейтинга и профиля разметку строят сами через
   js/рейтинг-экран.js кодом `document.querySelectorAll('.экран')` без
   ограничения родителем — поэтому и здесь выбран тот же голый селектор
   «.экран», а не «#приложение > .экран» (этим вторым приёмом в файле
   уже пользуется «видимыйГлавныйЭкран» для листа «⋯», но он бы не поймал
   общий экран, вставленный мимо #приложение).

   Запуск:
       node tests/шахматы-витрина-прячет-всё.js             — чистый прогон
       node tests/шахматы-витрина-прячет-всё.js --сломать   — ломающий прогон:
         портит КОПИЮ js/шахматы-экран.js в os.tmpdir() (настоящий файл
         не трогает), возвращая широкий приём назад к узкому списку по
         именам, — проверка пункта «а)» обязана покраснеть.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const os = require('os');

const КОРЕНЬ = path.join(__dirname, '..');
const ПУТЬ_ЭКРАНА_ОРИГИНАЛ = path.join(КОРЕНЬ, 'js', 'шахматы-экран.js');

const сломать = process.argv.indexOf('--сломать') !== -1;

// Настоящие правила хода — не наш файл, не меняются, берём через require
// (шахматы-правила.js умеет отдаваться и в Node, и в браузер, см. его хвост).
const ПравилаМодуль = require(path.join(КОРЕНЬ, 'js', 'шахматы-правила.js'));

/* Экраны шахматы.html «как в разметке»: лобби скрыто, доска видна —
   так страница выглядит без JS лобби (см. комментарий в самой html).
   Плюс посторонний «экран-профиля-игрока» — тот самый общий экран,
   который эта беда оставляла висеть поверх лобби. */
const ЭКРАНЫ_ПО_УМОЛЧАНИЮ = [
  'экран-лобби', 'экран-шахмат', 'экран-итога', 'экран-превращения',
  'экран-ничьей', 'экран-рекордов', 'экран-правил', 'экран-профиля-игрока'
];

/**
 * Поднять js/шахматы-экран.js в песочнице vm с поддельным DOM. classList —
 * настоящий (Set), document.querySelectorAll('.экран') находит узлы
 * из ЭКРАНЫ_ПО_УМОЛЧАНИЮ (заведены заранее, до первой строчки файла —
 * как разметка в настоящем браузере). window.ШахматыПравила — настоящий
 * модуль правил, иначе файл останавливает себя на первой же строчке.
 *
 * опции.лоббиВидноСразу — завести «экран-лобби» уже с классом
 *   «экран--виден» (сценарий б: с открытого лобби кнопка идёт на витрину).
 */
function поднятьШахматыЭкран(путь, опции) {
  опции = опции || {};
  const исходник = fs.readFileSync(путь, 'utf8');

  const узлыПоId = new Map();
  const корень = { appendChild(р) { привязать(р); return р; }, insertBefore(р) { привязать(р); return р; } };

  function привязать(узел) { узел.parentNode = корень; }

  function новыйУзел() {
    const классы = new Set();
    const слушатели = {};
    return {
      id: '',
      children: [],
      classList: {
        add(к) { классы.add(к); },
        remove(к) { классы.delete(к); },
        toggle(к, состояние) {
          const надо = состояние === undefined ? !классы.has(к) : Boolean(состояние);
          if (надо) классы.add(к); else классы.delete(к);
          return надо;
        },
        contains(к) { return классы.has(к); }
      },
      style: { setProperty() {}, removeProperty() {} },
      dataset: {}, textContent: '', innerHTML: '', value: '', disabled: false,
      setAttribute() {}, getAttribute() { return null; }, removeAttribute() {}, hasAttribute() { return false; },
      appendChild(р) { привязать(р); return р; },
      removeChild() {},
      insertBefore(р) { привязать(р); return р; },
      remove() {},
      focus() {}, blur() {},
      addEventListener(тип, ф) { (слушатели[тип] = слушатели[тип] || []).push(ф); },
      removeEventListener(тип, ф) {
        if (!слушатели[тип]) return;
        const где = слушатели[тип].indexOf(ф);
        if (где !== -1) слушатели[тип].splice(где, 1);
      },
      click() { (слушатели.click || []).slice().forEach(ф => ф({ target: this, stopPropagation() {} })); },
      querySelector() { return null; }, querySelectorAll() { return []; },
      closest() { return null; }, contains() { return false; },
      nextSibling: null, parentNode: корень,
      getBoundingClientRect() { return { width: 40, height: 40, top: 0, left: 0, right: 40, bottom: 40 }; }
    };
  }

  function получитьУзел(id) {
    if (узлыПоId.has(id)) return узлыПоId.get(id);
    const узел = новыйУзел();
    узел.id = id;
    узлыПоId.set(id, узел);
    return узел;
  }

  // Экраны — заранее, с class="экран", как в настоящей разметке.
  ЭКРАНЫ_ПО_УМОЛЧАНИЮ.forEach(id => получитьУзел(id).classList.add('экран'));
  получитьУзел('экран-шахмат').classList.add('экран--виден');           // доска видна по умолчанию
  получитьУзел('экран-профиля-игрока').classList.add('экран--виден');   // посторонний экран открыт поверх
  if (опции.лоббиВидноСразу) {
    получитьУзел('экран-лобби').classList.add('экран--виден');
    получитьУзел('экран-шахмат').classList.remove('экран--виден');
  }

  const хранилище = {};
  const localStorage = {
    getItem(к) { return (к in хранилище) ? хранилище[к] : null; },
    setItem(к, з) { хранилище[к] = String(з); },
    removeItem(к) { delete хранилище[к]; }
  };

  const документ = {
    getElementById: получитьУзел,
    createElement: новыйУзел,
    createTextNode: новыйУзел,
    createDocumentFragment: новыйУзел,
    querySelector() { return null; },
    querySelectorAll(селектор) {
      if (селектор === '.экран') {
        return Array.from(узлыПоId.values()).filter(у => у.classList.contains('экран'));
      }
      return [];
    },
    addEventListener() {}, removeEventListener() {},
    documentElement: новыйУзел(), body: новыйУзел(), head: новыйУзел(),
    readyState: 'complete'
  };

  const окно = {
    addEventListener() {}, removeEventListener() {},
    matchMedia() { return { matches: false, addEventListener() {}, addListener() {} }; },
    localStorage: localStorage,
    location: { search: '', href: '' },
    setTimeout, clearTimeout, setInterval, clearInterval,
    ШахматыПравила: ПравилаМодуль,
    ШахматыЛобби: {}   // достаточно правды: «лобби подключилось» — сам приём смотрит только на этот флаг
  };
  окно.document = документ;

  const песочница = {
    window: окно, document: документ,
    setTimeout, clearTimeout, setInterval, clearInterval,
    Math, Date, JSON, Number, String, Array, Object, Boolean, RegExp, Error, Map, Set, isFinite,
    console: { log() {}, warn() {}, error() {} }
  };
  песочница.globalThis = песочница;
  vm.createContext(песочница);
  vm.runInContext(исходник, песочница, { filename: 'js/шахматы-экран.js (витрина прячет всё)' });

  return { окно: окно, получитьУзел: получитьУзел };
}

/* =======================================================================
   ВЕСЬ НАБОР ПРОВЕРОК ОДНИМ ПРОГОНОМ.
   ======================================================================= */
function прогнать(путьЭкрана) {
  const строки = [];
  let провалов = 0;

  function проверить(имя, условие, подробности) {
    if (условие) {
      строки.push('OK    ' + имя);
    } else {
      провалов++;
      строки.push('ПЛОХО ' + имя + (подробности ? ' — ' + подробности : ''));
    }
  }

  /* --- а) лобби скрыто, посторонний экран профиля открыт поверх доски --- */
  let сценарийА = null;
  try {
    сценарийА = поднятьШахматыЭкран(путьЭкрана, {});
    проверить('а) js/шахматы-экран.js поднимается в песочнице (лобби скрыто)', true);
  } catch (сбой) {
    проверить('а) js/шахматы-экран.js поднимается в песочнице (лобби скрыто)', false, сбой.message);
  }
  if (сценарийА) {
    const узелПрофиля = сценарийА.получитьУзел('экран-профиля-игрока');
    const узелЛобби = сценарийА.получитьУзел('экран-лобби');
    const кнопкаНазад = сценарийА.получитьУзел('кнопка-назад');

    проверить('а) до клика посторонний «экран-профиля-игрока» видим (условие теста верно поставлено)',
      узелПрофиля.classList.contains('экран--виден'));
    проверить('а) до клика лобби скрыто (условие теста верно поставлено)',
      !узелЛобби.classList.contains('экран--виден'));

    кнопкаНазад.click();

    проверить('а) посторонний «экран-профиля-игрока» спрятан после «В меню» с доски',
      !узелПрофиля.classList.contains('экран--виден'));
    проверить('а) лобби показано после «В меню» с доски',
      узелЛобби.classList.contains('экран--виден'));
    проверить('а) доска спрятана вместе с посторонним экраном',
      !сценарийА.получитьУзел('экран-шахмат').classList.contains('экран--виден'));
    // На витрину в этом сценарии не уходим — переход внутри страницы.
    проверить('а) на index.html не ушли (переход остался внутри страницы, в лобби)',
      сценарийА.окно.location.href === '');
  }

  /* --- б) лобби уже открыто — кнопка ведёт на витрину, не трогая посторонний экран --- */
  let сценарийБ = null;
  try {
    сценарийБ = поднятьШахматыЭкран(путьЭкрана, { лоббиВидноСразу: true });
    проверить('б) js/шахматы-экран.js поднимается в песочнице (лобби уже открыто)', true);
  } catch (сбой) {
    проверить('б) js/шахматы-экран.js поднимается в песочнице (лобби уже открыто)', false, сбой.message);
  }
  if (сценарийБ) {
    const узелПрофиля = сценарийБ.получитьУзел('экран-профиля-игрока');
    const кнопкаНазад = сценарийБ.получитьУзел('кнопка-назад');

    кнопкаНазад.click();

    проверить('б) с открытого лобби «В меню» уводит на index.html (условие входа в широкую ветку сохранено)',
      /^index\.html/.test(сценарийБ.окно.location.href));
    проверить('б) эта ветка не трогает посторонний «экран-профиля-игрока» (широкий цикл стоит только в ветке «а»)',
      узелПрофиля.classList.contains('экран--виден'));
  }

  return { строки: строки, провалов: провалов };
}

/* =======================================================================
   ЗАПУСК
   ======================================================================= */

if (!сломать) {
  console.log('=== Шахматы: витрина прячет всё (обычный прогон) ===\n');
  const { строки, провалов } = прогнать(ПУТЬ_ЭКРАНА_ОРИГИНАЛ);
  строки.forEach(с => console.log(с));
  console.log('');
  console.log('Итого проверок: ' + строки.length + ', провалов: ' + провалов);
  process.exit(провалов > 0 ? 1 : 0);
} else {
  console.log('=== Шахматы: витрина прячет всё (ЛОМАЮЩИЙ прогон --сломать) ===\n');

  const оригинал = fs.readFileSync(ПУТЬ_ЭКРАНА_ОРИГИНАЛ, 'utf8');

  const ИСКОМОЕ_ШИРОКИЙ_ПРИЁМ =
    "      for (const экран of document.querySelectorAll('.экран')) {\r\n" +
    "        экран.classList.remove('экран--виден');\r\n" +
    "      }";
  const УЗКИЙ_СПИСОК_НАЗАД =
    "      for (const экран of [document.getElementById('экран-шахмат'), экранПравил]) {\r\n" +
    "        if (экран) экран.classList.remove('экран--виден');\r\n" +
    "      }";

  if (оригинал.indexOf(ИСКОМОЕ_ШИРОКИЙ_ПРИЁМ) === -1) {
    console.log('ОШИБКА: широкий приём не нашёлся в js/шахматы-экран.js — приём в файле поменялся,');
    console.log('обновите порчу в этом тесте.');
    process.exit(1);
  }

  const испорченный = оригинал.split(ИСКОМОЕ_ШИРОКИЙ_ПРИЁМ).join(УЗКИЙ_СПИСОК_НАЗАД);
  const временнаяПапка = fs.mkdtempSync(path.join(os.tmpdir(), 'шахматы-витрина-прячет-всё-'));
  const путьКопии = path.join(временнаяПапка, 'шахматы-экран.js');
  fs.writeFileSync(путьКопии, испорченный, 'utf8');
  console.log('Порча: копия — ' + путьКопии + ' (настоящий js/шахматы-экран.js не тронут).');
  console.log('Широкий приём заменён обратно на узкий список по именам («экран-шахмат», экранПравил).\n');

  let результат;
  try {
    результат = прогнать(путьКопии);
  } finally {
    try {
      fs.unlinkSync(путьКопии);
      fs.rmdirSync(временнаяПапка);
    } catch (е) { /* уборка временной папки необязательна для итога прогона */ }
  }

  результат.строки.forEach(с => console.log(с));
  console.log('\nПровалов на копии: ' + результат.провалов);

  const ожидание = 'а) посторонний «экран-профиля-игрока» спрятан после «В меню» с доски';
  const поймали = результат.строки.some(с => с.indexOf('ПЛОХО') === 0 && с.indexOf(ожидание) !== -1);

  console.log('');
  if (поймали) {
    console.log('ИТОГ ЛОМАЮЩЕГО ПРОГОНА: порча поймана — проверка покраснела, как и должна.');
    process.exit(0);
  } else {
    console.log('ИТОГ ЛОМАЮЩЕГО ПРОГОНА: ПРОВЕРКА СЛЕПАЯ — ожидаемая проверка не покраснела («' + ожидание + '»).');
    process.exit(1);
  }
}
