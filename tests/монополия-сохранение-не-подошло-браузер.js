const НЕГОДНАЯ = { version: 1, n: 4, seed: 17, actions: [{ p: 3, move: { type: 'buy' } }], id: 1, result: false };

async function сценарий(браузер, адрес, ключ, снимать) {
  const контекст = await браузер.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
  const страница = await контекст.newPage();
  const ошибки = [];
  страница.on('pageerror', function (о) { ошибки.push('исключение: ' + о.message); });
  страница.on('console', function (с) {
    if (с.type() === 'error' && !/Failed to load resource/.test(с.text())) ошибки.push('консоль: ' + с.text());
  });
  await подготовитьПодделку(страница, {});
  const открыть = async function () {
    await страница.goto(адрес + '/монополия.html', { waitUntil: 'load' });
    await страница.waitForSelector('#экран-лобби', { state: 'attached' });
  };
  try {
    // Опорная точка: чистая память — узла с сообщением нет, лобби открылось.
    await открыть();
    const чистый = await видЛобби(страница);
    проверить(чистый.узелЕсть, '[узел] в разметке монополии есть #mono-restore-note (не нашли — провал)');
    проверить(чистый.лобби && !чистый.узелВиден, '[чисто] при чистой памяти лобби открыто, а сообщения нет');

    // (а) негодная запись в память, (б) открыть заново.
    await страница.evaluate(function (д) { localStorage.setItem(д.ключ, JSON.stringify(д.запись)); }, { ключ: ключ, запись: НЕГОДНАЯ });
    await открыть();

    // (в) что видит человек.
    const в = await видЛобби(страница);
    проверить(в.лобби, '[лобби] с негодной записью лобби всё равно открылось');
    проверить(в.узелВиден, '[сообщение] узел с сообщением виден');
    проверить(в.текст.indexOf(СЛОВА) !== -1, '[сообщение] в нём слова «' + СЛОВА + '» (там: «' + в.текст + '»)');
    проверить(в.вЭкране, '[сообщение] узел целиком в пределах экрана шириной 390');
    проверить(!в.продолжитьВидна, '[стёрто] кнопки «Продолжить партию» нет — негодная партия не подхвачена');
    const осталось = await страница.evaluate(function (к) { return localStorage.getItem(к); }, ключ);
    проверить(осталось === null, '[стёрто] негодная запись стёрта из памяти (осталось: ' + (осталось === null ? 'ничего' : осталось.slice(0, 40)) + ')');
    проверить(ошибки.length === 0, '[консоль] красных ошибок при открытии нет' + (ошибки.length ? ': ' + ошибки.join(' | ') : ''));

    // (г) снимок.
    if (снимать) {
      fs.mkdirSync(path.dirname(СНИМОК), { recursive: true });
      await страница.screenshot({ path: СНИМОК });
      проверить(fs.existsSync(СНИМОК) && fs.statSync(СНИМОК).size > 1000, '[снимок] снимок лобби сохранён: tests/снимки/монополия-сохранение-не-подошло-390.png');
    }

    // (д) новая партия.
    await страница.click('#mono-bots');
    await страница.click('#mono-start');
    const идёт = await страница.waitForSelector('#экран-игры.экран--виден', { timeout: 8000 }).then(function () { return true; }, function () { return false; });
    проверить(идёт, '[партия] после «Начать игру» открылся экран игры');
    const узелПосле = await страница.evaluate(function () {
      const у = document.getElementById('mono-restore-note');
      return у ? у.classList.contains('скрыт') : null;
    });
    проверить(узелПосле === true, '[спрятан] после начала новой партии узел спрятан (класс «скрыт»)');
    const запись = await страница.evaluate(function (к) {
      try { return JSON.parse(localStorage.getItem(к)); } catch (е) { return null; }
    }, ключ);
    проверить(Boolean(запись && Array.isArray(запись.actions) && запись.version === 1), '[партия] новая партия записана в память');
    проверить((await страница.locator('#mono-error').innerText()) === '', '[партия] на экране игры нет надписи об ошибке');

    // (е-1) годная запись переживает перезагрузку, сообщения нет.
    await открыть();
    const годная = await видЛобби(страница);
    проверить(!годная.узелВиден, '[годная] с целой записью в памяти сообщения нет');
    проверить(годная.продолжитьВидна, '[годная] с целой записью есть кнопка «Продолжить партию» (защита не убила годную)');

    // (е-2) чистая память.
    await страница.evaluate(function () { localStorage.clear(); });
    await открыть();
    const пустой = await видЛобби(страница);
    проверить(пустой.лобби && !пустой.узелВиден, '[чисто] после перезагрузки с чистой памятью лобби открыто, сообщения не видно');
    проверить(!пустой.продолжитьВидна, '[чисто] и «Продолжить партию» нет');
    проверить(ошибки.length === 0, '[консоль] за весь сценарий красных ошибок нет' + (ошибки.length ? ': ' + ошибки.join(' | ') : ''));

    // ---- Сценарии 30.09: слова показываются один раз, запись новее не стирается ----
    const БИТАЯ = { version: 1, n: 3, seed: 5, actions: [{ p: 0, move: { type: 'end' } }], id: 1, result: false };
    const положить = function (значение) {
      return страница.evaluate(function (д) { localStorage.setItem(д.к, д.з); }, { к: ключ, з: JSON.stringify(значение) });
    };
    const взять = function () { return страница.evaluate(function (к) { return localStorage.getItem(к); }, ключ); };

    // 1. Битая запись: слова в лобби, записи в памяти нет.
    await положить(БИТАЯ);
    await открыть();
    const с1 = await видЛобби(страница);
    проверить(с1.лобби && с1.узелВиден && с1.текст.indexOf(СЛОВА) !== -1, '[сц1] битая запись: в лобби слова «не подошла» (там: «' + с1.текст + '»)');
    проверить((await взять()) === null, '[сц1] битая запись стёрта из памяти');
    проверить(!с1.продолжитьВидна, '[сц1] «Продолжить» не видна');

    // 2. Играть с ботами, вернуться стрелкой в лобби: слов нет.
    await страница.click('#mono-bots');
    await страница.click('#mono-start');
    const идёт2 = await страница.waitForSelector('#экран-игры.экран--виден', { timeout: 8000 }).then(function () { return true; }, function () { return false; });
    проверить(идёт2, '[сц2] партия с ботами открылась');
    // Верхняя «‹» в Telegram спрятана (её заменяет системная стрелка) — жмём стрелку подделки.
    await страница.evaluate(function () { window.ПоддельныйТелеграм.нажатьНазад(); });
    const с2 = await видЛобби(страница);
    проверить(с2.лобби, '[сц2] стрелкой вернулись в лобби');
    проверить(!с2.узелВиден && с2.текст === '', '[сц2] после партии слов нет (там: «' + с2.текст + '»)');

    // 3. Снова битая запись: слова есть; после обновления — слов нет.
    await положить(БИТАЯ);
    await открыть();
    const с3а = await видЛобби(страница);
    проверить(с3а.узелВиден && с3а.текст.indexOf(СЛОВА) !== -1, '[сц3] снова битая запись: слова есть');
    await открыть();
    const с3б = await видЛобби(страница);
    проверить(с3б.лобби && !с3б.узелВиден, '[сц3] после обновления страницы слов нет (записи уже нет)');

    // 4. Запись новее известной версии: слов нет, запись цела, «Продолжить» не видна, одно предупреждение.
    const НОВЕЕ = JSON.stringify(Object.assign({}, БИТАЯ, { version: 99 }));
    await страница.evaluate(function (д) { localStorage.setItem(д.к, д.з); }, { к: ключ, з: НОВЕЕ });
    const предупреждения = [];
    страница.on('console', function (с) { if (с.type() === 'warning') предупреждения.push(с.text()); });
    await открыть();
    const с4 = await видЛобби(страница);
    проверить(с4.лобби && !с4.узелВиден, '[сц4] запись версии 99: слов нет');
    проверить((await взять()) === НОВЕЕ, '[сц4] запись версии 99 в памяти ЦЕЛА');
    проверить(!с4.продолжитьВидна, '[сц4] «Продолжить» не видна');
    проверить(предупреждения.filter(function (т) { return /новее/.test(т); }).length === 1, '[сц4] в консоли ровно одно предупреждение «новее» (их: ' + предупреждения.length + ')');
    проверить(ошибки.length === 0, '[консоль] за все сценарии красных ошибок нет' + (ошибки.length ? ': ' + ошибки.join(' | ') : ''));

    // 5. Вход в сетевую партию из лобби со словами: своего стенда сервера комнат здесь нет.
    console.log('  --   — [сц5] сетевая партия: не проверено в браузере (нет стенда сервера комнат; покрыто node-проверкой на поддельном DOM)');

    // Снимок именно лобби со словами (перезаписываем итоговым видом).
    if (снимать) {
      await положить(БИТАЯ);
      await открыть();
      await страница.screenshot({ path: СНИМОК });
    }
  } finally {
    await контекст.close();
  }
}

/* ---------- Обычный прогон ---------- */

async function прогнать(файлЭкрана) {
  const текстЭкрана = fs.readFileSync(файлЭкрана || ЭКРАН_НАСТОЯЩИЙ, 'utf8');
  console.log('=== Монополия: негодная сохранённая партия — в настоящем браузере, ширина 390 ===');
  const ключ = найтиКлюч(текстЭкрана);
  if (!проверить(Boolean(ключ), '[ключ] ключ сохранённой партии найден в игры/монополия/монополия-экран.js' + (ключ ? ' («' + ключ + '»)' : ''))) return;
  const сервер = await поднятьСервер(файлЭкрана);
  const адрес = 'http://127.0.0.1:' + сервер.address().port;
  console.log('стенд: ' + адрес + ' (свой, не боевой 8790)' + (файлЭкрана ? '; экран из копии: ' + файлЭкрана : ''));
  let браузер = null;
  try {
    браузер = await chromium.launch();
    await сценарий(браузер, адрес, ключ, !файлЭкрана);
  } finally {
    if (браузер) await браузер.close();
    сервер.close();
    console.log('Стенд закрыт (процесс ' + process.pid + ').');
  }
}

