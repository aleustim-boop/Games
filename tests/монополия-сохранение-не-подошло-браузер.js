function найтиКлюч(текст) {
  const совпало = /\bKEY\s*=\s*"([^"]+)"/.exec(текст);
  return совпало ? совпало[1] : null;
}

/* ---------- Файловый сервер стенда ---------- */

const ТИПЫ = {
  '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8', '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg',
  '.webp': 'image/webp', '.woff2': 'font/woff2', '.mp3': 'audio/mpeg', '.ogg': 'audio/ogg',
  '.wav': 'audio/wav'
};

function поднятьСервер(файлЭкрана) {
  const сервер = http.createServer(function (запрос, ответ) {
    let адрес;
    try { адрес = decodeURIComponent(запрос.url.split('?')[0]); } catch (е) { ответ.writeHead(400); ответ.end(); return; }
    if (адрес === '/') адрес = '/монополия.html';
    const относительный = path.normalize(адрес).replace(/^(\.\.[\\/])+/, '').replace(/^[\\/]+/, '');
    const части = относительный.split(/[\\/]/).filter(Boolean);
    if (адрес.toLowerCase().indexOf('.env') !== -1 || (части[0] || '').toLowerCase() === 'bot' ||
        части.some(function (ч) { return ч.charAt(0) === '.'; })) {
      ответ.writeHead(403); ответ.end('закрыто'); return;
    }
    let файл = path.join(ПРОЕКТ, относительный);
    if (файлЭкрана && относительный.split(path.sep).join('/') === ЭКРАН_ОТНОСИТЕЛЬНО) файл = файлЭкрана;
    fs.readFile(файл, function (ошибка, данные) {
      if (ошибка) { ответ.writeHead(404); ответ.end('нет файла'); return; }
      ответ.writeHead(200, { 'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'application/octet-stream', 'Cache-Control': 'no-store' });
      ответ.end(данные);
    });
  });
  return new Promise(function (готово, беда) {
    сервер.once('error', беда);
    сервер.listen(0, '127.0.0.1', function () { готово(сервер); });
  });
}

/* ---------- Что видно в лобби ---------- */

function видЛобби(страница) {
  return страница.evaluate(function () {
    const у = document.getElementById('mono-restore-note');
    const лобби = document.getElementById('экран-лобби');
    const продолжить = document.getElementById('mono-resume');
    const рамка = у ? у.getBoundingClientRect() : null;
    const видно = function (е) {
      if (!е || е.classList.contains('скрыт')) return false;
      const р = е.getBoundingClientRect();
      const ст = getComputedStyle(е);
      return р.width > 0 && р.height > 0 && ст.visibility !== 'hidden' && ст.display !== 'none';
    };
    return {
      узелЕсть: Boolean(у),
      узелВиден: видно(у),
      текст: у ? у.textContent.trim() : '',
      вЭкране: Boolean(рамка && рамка.left >= 0 && рамка.right <= window.innerWidth + 0.5 && рамка.width > 0),
      лобби: Boolean(лобби && лобби.classList.contains('экран--виден')),
      продолжитьВидна: видно(продолжить)
    };
  });
}

