  проверка('итог: столицы мои — причина словами сети', м.узел('захват-итог-причина').textContent === 'Все столицы ваши',
    м.узел('захват-итог-причина').textContent);

  // Готовые строки сети (отменённая партия) — вместо посчитанных.
  м.экран.показатьИтог(данныеСети(1, { заголовок: 'Партия отменена', причинаСловами: 'Сервер перезапускался' }));
