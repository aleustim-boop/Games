// Атрибут open — как в браузере: «‹» экрана ищет открытое окно селектором dialog[open].
function оживитьОкна(документ) {
  документ.querySelectorAll('dialog').forEach(окно => {
    окно.open = false;
    окно.showModal = () => { окно.open = true; окно.setAttribute('open', ''); };
    окно.close = () => { окно.open = false; окно.removeAttribute('open'); };
  });
}

/** Esc на окне, как в браузере: событие cancel, и если его не отменили — окно закрывается. Ответ — отменили ли. */
function нажатьEsc(окно) {
  let отменили = false;
  окно.dispatchEvent({ type: 'cancel', target: окно, preventDefault() { отменили = true; }, stopPropagation() {} });
  if (!отменили) окно.close();
  return отменили;
}

