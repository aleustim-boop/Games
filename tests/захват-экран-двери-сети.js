/** Двери сети — следилки: запоминают, кого и с чем позвал экран. */
function двериСледилки(м) {
  const двери = {};
  ['приИзменении', 'приГотово', 'приИзменить', 'приВиде', 'приПротяжке', 'приПропуске', 'приДолгомКасанииСОстатком',
    'ещё', 'выйти', 'сдаться'].forEach(имя => {
    двери[имя] = function () { м.вызовыСети.push({ дверь: имя, доводы: Array.prototype.slice.call(arguments) }); };
  });
  двери.словаВыхода = () => null;
  return двери;
}

/** Сеть берёт стол и ставит на него партию: места а, б, в; «я» — а. */
function взятьСтолСети(м) {
  const стол = м.экран.столДляСети(двериСледилки(м));
  м.экран.показатьЭкран('экран-игры');
  const партия = м.Правила.новаяПартия({ игроки: ['а', 'б', 'в'], люди: ['а', 'б', 'в'], сейчас: 0, раундовЗахвата: 10 }, () => 0.3);
  const инфо = { имена: { а: 'Аня', б: 'Боря', в: 'Вера' }, готовы: {}, боты: {}, спят: {} };
  стол.задатьРаскрытие(false);
  стол.начатьРаунд(партия, 'а', инфо, null);
  стол.показатьСлой(ШИРИНА_КАРТЫ);
  return { стол: стол, партия: партия, инфо: инфо };
}

