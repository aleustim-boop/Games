async function главная() {
  const шаги = [проверитьДвери, проверитьИтог, проверитьУходИзИтога, проверитьСледыБотов, проверитьПозднийРейтинг, проверитьСтолицыБотов,
    проверитьПластину, проверитьКонечнуюКарту, проверитьПоставитьСюда];
  for (const шаг of шаги) {
    try { await шаг(); } catch (ошибка) {
      всего++; провалов++;
      console.log('ПРОВАЛ: шаг «' + шаг.name + '» упал — ' + (ошибка && ошибка.stack ? ошибка.stack.split('\n').slice(0, 3).join(' / ') : ошибка));
    }
  }
  console.log('Итого проверок: ' + всего + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
}

