/* ---------- 7. «Поставить сюда» в сети молчит ---------- */

function проверитьПоставитьСюда() {
  const м = мир();
  const с = взятьСтолСети(м);
  const своя = с.партия.хозяева.findIndex((х, н) => н > 0 && х === 'а');
  проверка('поставить: своя область нашлась (ноль — провал)', своя > 0, String(своя));
  const раскладка = м.КартаВид.собратьРаскладку(с.партия, { ширина: ШИРИНА_КАРТЫ });
  const шайба = раскладка.шайбы.filter(ш => ш.область === своя)[0];
  проверка('поставить: у своей области есть точка на карте (ноль — провал)', !!шайба);
  проверка('поставить: остаток подкрепления есть', (с.партия.подкрепление.а || 0) > 0, JSON.stringify(с.партия.подкрепление));
  if (!шайба) return;
  const палец = вид => м.узел('захват-карта').dispatchEvent({ type: вид, pointerId: 1, clientX: шайба.x, clientY: шайба.y,
    preventDefault() {}, stopPropagation() {} });
  const черновикДо = JSON.stringify(с.стол.черновик());
  палец('pointerdown');
  м.часы.прошло(м.окно.ЗахватСтол.ДОЛГОЕ_КАСАНИЕ_МС + 100);
  палец('pointerup');
  const касания = м.вызовыСети.filter(в => в.дверь === 'приДолгомКасанииСОстатком');
  проверка('поставить: долгое касание ушло в дверь сети со своей областью', касания.length === 1 && касания[0].доводы[0] === своя,
    JSON.stringify(касания));
  проверка('поставить: лист экрана «Поставить сюда» не открылся', !м.видна('захват-поставить'));
  м.нажать('захват-поставить-все');
  м.нажать('захват-поставить-да');
  проверка('поставить: кнопки листа экрана черновик не меняют', JSON.stringify(с.стол.черновик()) === черновикДо, JSON.stringify(с.стол.черновик()));
  проверка('поставить: правок черновика сеть не получала', м.звалиСеть('приИзменении') === 0, 'правок ' + м.звалиСеть('приИзменении'));
}

