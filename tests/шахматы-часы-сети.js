'use strict';

/* =====================================================================
   ПРОВЕРКА ЧАСОВ ШАХМАТ ПО СЕТИ (server/игры/шахматы.js, этап Э8а).

   Время двигаем подменой функции «сейчас» у модуля игры — ждать минуты
   не нужно. Проверяем: списание и добавку Фишера, поражение по времени,
   ничью при голом короле соперника, «без часов» при чужом контроле и
   часы в виде у обоих игроков.

   Запуск:        node tests/шахматы-часы-сети.js
   Ломающий:      node tests/шахматы-часы-сети.js --сломать <путь к копии>
                  (копия server/игры/шахматы.js, испорченная во временной
                  папке; проверка обязана покраснеть)
   ===================================================================== */

const path = require('path');
const fs = require('fs');
const Module = require('module');

const ПАПКА_ИГР = path.join(__dirname, '..', 'server', 'игры');
const НАСТОЯЩИЙ = path.join(ПАПКА_ИГР, 'шахматы.js');

/* Какой файл игры проверяем: настоящий или испорченную копию. Приём тот
   же, что в tests/шахматы-сервер-правила.js: текст копии собираем как
   модуль, «живущий» в server/игры, — тогда её относительные require
   находят настоящие правила, и копия как есть работает так же, как файл. */
function загрузитьИгру() {
  const i = process.argv.indexOf('--сломать');
  if (i === -1) return require(НАСТОЯЩИЙ);
  const копия = process.argv[i + 1];
  if (!копия || !fs.existsSync(копия)) {
    console.error('Для --сломать нужен путь к существующей копии файла игры');
    process.exit(2);
  }
  if (path.resolve(копия) === path.resolve(НАСТОЯЩИЙ)) {
    console.error('--сломать портит только КОПИЮ, а не настоящий файл');
    process.exit(2);
  }
  const имя = path.join(ПАПКА_ИГР, '__копия-для-порчи__.js');
  const модуль = new Module(имя, null);
  модуль.filename = имя;
  модуль.paths = Module._nodeModulePaths(ПАПКА_ИГР);
  модуль._compile(fs.readFileSync(копия, 'utf8'), имя);
  return модуль.exports;
}

const Шахматы = загрузитьИгру();
const Правила = require(path.join(__dirname, '..', 'js', 'шахматы-правила.js'));

let проверок = 0;
let провалов = 0;
function проверить(название, верно, подробно) {
  проверок++;
  if (верно) {
    console.log('  ок   ' + название);
  } else {
    провалов++;
    console.log('  ПРОВАЛ ' + название + (подробно !== undefined ? ' — ' + JSON.stringify(подробно) : ''));
  }
}

/* Подменяемое время: часы модуля читают только его. */
let время = 1000000;
Шахматы.сейчас = function () { return время; };
function прошло(мс) { время += мс; }

/* Ноль найденного — провал: без этих дверей проверять нечего. */
проверить('у игры есть ходПоПросрочке', typeof Шахматы.ходПоПросрочке === 'function');
проверить('у игры есть остатокВремениНаХод', typeof Шахматы.остатокВремениНаХод === 'function');
проверить('Правила умеют партияИзFEN', typeof Правила.партияИзFEN === 'function');
if (провалов > 0) закончить();

function новаяПартия(контроль) {
  const партия = Шахматы.раздать('А', { игроки: ['А', 'Б'], контрольШахмат: контроль });
  return партия;
}
function белыйИгрок(партия) { return партия.цвета['А'] === Правила.БЕЛЫЕ ? 'А' : 'Б'; }
function чёрныйИгрок(партия) { return белыйИгрок(партия) === 'А' ? 'Б' : 'А'; }

/* ---------- 1. Блиц: списание и добавка Фишера ---------- */
console.log('Блиц 5 + 3: списание и добавка');
{
  const партия = новаяПартия('блиц');
  const белые = белыйИгрок(партия);
  const чёрные = чёрныйИгрок(партия);
  проверить('часы заведены', Boolean(партия.часы));
  проверить('старт 5 минут у обоих', партия.часы && партия.часы.белые === 300000 && партия.часы.чёрные === 300000,
    партия.часы);

  прошло(10000);
  const ответ = Шахматы.сделатьХод(партия, белые, { действие: 'ход', откуда: 'e2', куда: 'e4' });
  проверить('ход белых принят', ответ.принято, ответ);
  проверить('белые: 300 − 10 + 3 = 293 с', партия.часы.белые === 293000, партия.часы.белые);
  проверить('чёрные не тронуты', партия.часы.чёрные === 300000, партия.часы.чёрные);

  прошло(4000);
  проверить('остатокВремениНаХод = остаток чёрных в секундах (296)',
    Шахматы.остатокВремениНаХод(партия) === 296, Шахматы.остатокВремениНаХод(партия));

  const видБелых = Шахматы.видДляИгрока(партия, белые, {});
  const видЧёрных = Шахматы.видДляИгрока(партия, чёрные, {});
  for (const [кто, вид] of [['белых', видБелых], ['чёрных', видЧёрных]]) {
    const ч = вид.часы;
    проверить('в виде ' + кто + ' есть часы', Boolean(ч), вид.часы);
    if (!ч) continue;
    проверить('вид ' + кто + ': белые 293000', ч.белые === 293000, ч.белые);
    проверить('вид ' + кто + ': чёрные 296000 (идут)', ч.чёрные === 296000, ч.чёрные);
    проверить('вид ' + кто + ': идут у чёрных', ч.идут === 'b', ч.идут);
    проверить('вид ' + кто + ': время сервера', ч.сервер === время, ч.сервер);
  }

  прошло(6000);
  const ответЧёрных = Шахматы.сделатьХод(партия, чёрные, { действие: 'ход', откуда: 'e7', куда: 'e5' });
  проверить('ход чёрных принят', ответЧёрных.принято, ответЧёрных);
  проверить('чёрные: 300 − 10 + 3 = 293 с', партия.часы.чёрные === 293000, партия.часы.чёрные);
  проверить('после хода чёрных идут часы белых',
    Шахматы.видДляИгрока(партия, белые, {}).часы.идут === 'w');
}

