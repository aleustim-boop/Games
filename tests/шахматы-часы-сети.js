/* ---------- 3. Просрочка — поражение ---------- */
console.log('Просрочка — поражение по времени');
{
  const партия = новаяПартия('блиц');
  const белые = белыйИгрок(партия);
  const чёрные = чёрныйИгрок(партия);
  Шахматы.сделатьХод(партия, белые, { действие: 'ход', откуда: 'e2', куда: 'e4' });

  прошло(100000);
  проверить('до срока ходПоПросрочке ничего не делает', Шахматы.ходПоПросрочке(партия) === null);
  проверить('партия идёт', партия.завершена === false);

  прошло(250000);   // у чёрных было 300 с, прошло 350
  const опоздал = Шахматы.сделатьХод(партия, чёрные, { действие: 'ход', откуда: 'e7', куда: 'e5' });
  проверить('опоздавший ход не принят', опоздал.принято === false, опоздал);

  const итог = Шахматы.ходПоПросрочке(партия);
  проверить('ходПоПросрочке сработал за чёрных', Boolean(итог) && итог.ктоСделал === чёрные, итог);
  проверить('партия закончена', партия.завершена === true);
  проверить('победили белые', партия.результат === белые, партия.результат);
  проверить('проиграли чёрные', партия.проигравшие.length === 1 && партия.проигравшие[0] === чёрные,
    партия.проигравшие);
  const вид = Шахматы.видДляИгрока(партия, белые, {});
  проверить('в итоге причина «время вышло»', вид.итог && вид.итог.причина === 'время вышло', вид.итог);
  проверить('часы стоят', вид.часы && вид.часы.идут === null, вид.часы);
  проверить('у чёрных ноль', вид.часы && вид.часы.чёрные === 0, вид.часы);
  проверить('остатокВремениНаХод после конца — бесконечность',
    Шахматы.остатокВремениНаХод(партия) === Infinity);
  проверить('повторная просрочка ничего не делает', Шахматы.ходПоПросрочке(партия) === null);
}

/* ---------- 4. Просрочка при голом короле соперника — ничья ---------- */
console.log('Просрочка, а у соперника один король — ничья');
{
  const партия = новаяПартия('блиц');
  /* Белые: король и ферзь, ходят белые. Чёрные: один король. Упал флаг
     белых — мата чёрным ставить нечем. */
  партия.позиция = Правила.партияИзFEN('4k3/8/8/8/8/8/8/3QK3 w - - 0 1');
  партия.часы.с_какого_момента = время;
  прошло(301000);
  const итог = Шахматы.ходПоПросрочке(партия);
  проверить('просрочка сработала', Boolean(итог));
  проверить('партия закончена', партия.завершена === true);
  проверить('это ничья', партия.ничья === true && партия.результат === null,
    { ничья: партия.ничья, результат: партия.результат });
  проверить('проигравших нет', партия.проигравшие.length === 0, партия.проигравшие);
}
{
  /* Обратный случай: упал флаг у голого короля — соперник с ферзём выигрывает. */
  const партия = новаяПартия('блиц');
  партия.позиция = Правила.партияИзFEN('4k3/8/8/8/8/8/8/3QK3 b - - 0 1');
  партия.часы.с_какого_момента = время;
  прошло(301000);
  Шахматы.ходПоПросрочке(партия);
  проверить('голый король просрочил — белые выиграли',
    партия.завершена === true && партия.результат === белыйИгрок(партия), партия.результат);
}

/* ---------- 5. Чужой контроль — без часов ---------- */
console.log('Без часов');
for (const слово of ['нет', 'пуля', '', undefined, 'toString', '__proto__', 5]) {
  const партия = новаяПартия(слово);
  проверить('контроль ' + JSON.stringify(слово) + ' — часов нет', партия.часы === undefined, партия.часы);
  const вид = Шахматы.видДляИгрока(партия, 'А', {});
  проверить('контроль ' + JSON.stringify(слово) + ' — в виде поля часов нет', !('часы' in вид));
  проверить('контроль ' + JSON.stringify(слово) + ' — остаток бесконечен',
    Шахматы.остатокВремениНаХод(партия) === Infinity);
  прошло(10 * 60 * 60 * 1000);
  проверить('контроль ' + JSON.stringify(слово) + ' — просрочки не бывает',
    Шахматы.ходПоПросрочке(партия) === null && партия.завершена === false);
}

/* ---------- 6. Сдача останавливает часы ---------- */
console.log('Сдача останавливает часы');
{
  const партия = новаяПартия('рапид');
  прошло(5000);
  Шахматы.сделатьХод(партия, белыйИгрок(партия), { действие: 'сдаться' });
  const было = Шахматы.видДляИгрока(партия, 'А', {}).часы;
  прошло(60000);
  const стало = Шахматы.видДляИгрока(партия, 'А', {}).часы;
  проверить('после сдачи часы стоят', было && стало && стало.идут === null && стало.белые === было.белые,
    { было: было, стало: стало });
  проверить('последний ход оплачен: у белых 595 с', стало && стало.белые === 595000, стало);
}

/* ---------- 7. Ничья по соглашению останавливает часы ---------- */
console.log('Ничья по соглашению останавливает часы');
{
  const партия = новаяПартия('блиц');
  const белые = белыйИгрок(партия);
  const чёрные = чёрныйИгрок(партия);
  прошло(2000);
  Шахматы.сделатьХод(партия, белые, { действие: 'ничья' });
  const ответ = Шахматы.сделатьХод(партия, чёрные, { действие: 'ничья-да' });
  проверить('ничья принята', ответ.принято && партия.завершена && партия.ничья === true, ответ);
  const было = Шахматы.видДляИгрока(партия, белые, {}).часы;
  прошло(120000);
  const стало = Шахматы.видДляИгрока(партия, чёрные, {}).часы;
  проверить('после ничьей часы стоят', было && стало && стало.идут === null &&
    стало.белые === было.белые && стало.чёрные === было.чёрные, { было: было, стало: стало });
  проверить('после ничьей у белых 298 с', стало && стало.белые === 298000, стало);
}

/* ---------- 8. Партию закрыла комната сама (отмена при уходе) ---------- */
console.log('Партию закрыли снаружи — время не течёт');
{
  const партия = новаяПартия('рапид');
  прошло(3000);
  /* Ровно так закрывает партию server/комнаты.js при отмене: три поля,
     мимо правил и мимо записатьИтог. */
  партия.завершена = true;
  партия.результат = null;
  партия.проигравшие = [];
  const было = Шахматы.видДляИгрока(партия, 'А', {}).часы;
  прошло(60000);
  const стало = Шахматы.видДляИгрока(партия, 'А', {}).часы;
  проверить('цифры не меняются после закрытия снаружи', было && стало &&
    стало.белые === было.белые && стало.чёрные === было.чёрные, { было: было, стало: стало });
  проверить('часы не идут', стало && стало.идут === null, стало);
  проверить('остатокВремениНаХод — бесконечность', Шахматы.остатокВремениНаХод(партия) === Infinity);
}

/* ---------- 9. Ход на последних миллисекундах ---------- */
console.log('Ход с остатком 1–50 мс принимается');
for (const запас of [1, 50]) {
  const партия = новаяПартия('блиц');
  прошло(300000 - запас);
  const ответ = Шахматы.сделатьХод(партия, белыйИгрок(партия), { действие: 'ход', откуда: 'e2', куда: 'e4' });
  проверить('остаток ' + запас + ' мс — ход принят', ответ.принято === true, ответ);
  проверить('остаток ' + запас + ' мс — белым ' + (запас + 3000) + ' мс с добавкой',
    партия.часы.белые === запас + 3000, партия.часы.белые);
  проверить('остаток ' + запас + ' мс — партия идёт', партия.завершена === false);
}

закончить();

function закончить() {
  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
  process.exit(провалов > 0 ? 1 : 0);
}
