/* =====================================================================
   Проверка ограничений подкидывания и «бухгалтерии» отбоя.

   Автопрогон-правил проверяет общие вещи (карты не теряются, побито
   по правилам). Здесь — то, что он НЕ проверял:

   1. Нельзя выложить больше неотбитых карт, чем карт в руке
      у того, кто отбивается. Иначе ему нечем крыть, и это уже не игра.
   2. В отбой уходят только полные пары «атака + защита»,
      поэтому карт в отбое всегда чётное число.
   3. Отбой только растёт: карты оттуда никогда не возвращаются.
   4. Пока подход идёт, атакующий не меняется; меняется только
      после того, как стол опустел.
   5. Рука не бывает отрицательной, и одна и та же карта не лежит
      одновременно в руке и на столе.

   Запуск:  node tests/проверка-ограничений.js [сколько партий]
   ===================================================================== */

'use strict';

const игра = require(require('path').join(__dirname, '..', 'js', 'game.js'));

const ПАРТИЙ = Number(process.argv[2]) || 1500;
const ПРЕДЕЛ_ХОДОВ = 500;

// Свой генератор случайных чисел: по номеру партии раздача повторяется.
let зерно = 2024;
Math.random = function () {
  зерно = (зерно * 1103515245 + 12345) % 2147483648;
  return зерно / 2147483648;
};

const беды = [];
function записать(текст) {
  if (беды.length < 10 && беды.indexOf(текст) === -1) беды.push(текст);
}

function имя(карта) { return карта.имя + карта.масть; }

function неотбитых(п) {
  let счёт = 0;
  for (const пара of п.стол) if (!пара.защита) счёт++;
  return счёт;
}

/** Игрок, который ходит наугад: так перебирается больше положений. */
function случайныйХод(п, игрок) {
  const фаза = игра.фаза(п);
  const рука = п.руки[игрок];

  if (фаза === 'защита') {
    const варианты = [];
    п.стол.forEach(function (пара, iПары) {
      if (пара.защита) return;
      рука.forEach(function (карта, iКарты) {
        if (игра.бьёт(карта, пара.атака, п.козырь)) варианты.push([iПары, iКарты]);
      });
    });
    if (варианты.length === 0 || Math.random() < 0.3) { игра.объявитьБеру(п); return; }
    const в = варианты[Math.floor(Math.random() * варианты.length)];
    игра.отбить(п, в[0], в[1]);
    return;
  }

  const годные = [];
  for (let i = 0; i < рука.length; i++) if (игра.можноПоложить(п, рука[i])) годные.push(i);
  if (годные.length === 0 || (фаза !== 'атака' && Math.random() < 0.4)) { игра.завершитьПодход(п); return; }
  игра.положитьВАтаку(п, игрок, годные[Math.floor(Math.random() * годные.length)]);
}

let проверок = 0;

for (let н = 1; н <= ПАРТИЙ; н++) {
  зерно = н * 15485863 + 7;
  const п = игра.создатьПартию();
  let шагов = 0;
  let отбойБыло = 0;
  let атакующийБыл = п.атакует;
  let столБыл = 0;

  while (!п.завершена && шагов++ < ПРЕДЕЛ_ХОДОВ) {
    const кто = игра.ктоХодит(п);
    случайныйХод(п, кто);
    проверок++;

    // 1. Неотбитых карт не больше, чем карт у отбивающегося
    const защитник = игра.защищается(п);
    if (неотбитых(п) > п.руки[защитник].length) {
      записать('партия ' + н + ': на столе ' + неотбитых(п) + ' неотбитых карт, а у отбивающегося в руке только ' +
        п.руки[защитник].length + ' — крыть нечем, так подкидывать нельзя');
    }

    // 2. В отбое всегда полные пары
    if (п.отбой.length % 2 !== 0) {
      записать('партия ' + н + ': в отбое ' + п.отбой.length + ' карт — нечётное число, значит туда попала неотбитая карта');
    }

    // 3. Отбой только растёт
    if (п.отбой.length < отбойБыло) {
      записать('партия ' + н + ': из отбоя пропали карты (было ' + отбойБыло + ', стало ' + п.отбой.length + ')');
    }
    отбойБыло = п.отбой.length;

    // 4. Атакующий меняется только на пустом столе
    if (п.атакует !== атакующийБыл && столБыл > 0 && п.стол.length > 0) {
      записать('партия ' + н + ': атакующий сменился прямо посреди подхода');
    }
    атакующийБыл = п.атакует;
    столБыл = п.стол.length;

    // 5. Одна карта не лежит в двух местах
    const где = new Map();
    const добавить = (карта, место) => {
      if (где.has(карта)) записать('партия ' + н + ': карта ' + имя(карта) + ' лежит и в «' + где.get(карта) + '», и в «' + место + '»');
      где.set(карта, место);
    };
    п.руки.человек.forEach(к => добавить(к, 'руке человека'));
    п.руки.бот.forEach(к => добавить(к, 'руке бота'));
    п.колода.forEach(к => добавить(к, 'колоде'));
    п.отбой.forEach(к => добавить(к, 'отбое'));
    п.стол.forEach(пара => { добавить(пара.атака, 'столе'); if (пара.защита) добавить(пара.защита, 'столе'); });

    if (беды.length >= 10) break;
  }

  if (!п.завершена) записать('партия ' + н + ': не закончилась за ' + ПРЕДЕЛ_ХОДОВ + ' ходов');
  if (беды.length >= 10) break;
}

console.log('=== Проверка ограничений подкидывания и отбоя ===');
console.log('партий: ' + ПАРТИЙ + ', проверок после ходов: ' + проверок);
if (беды.length === 0) {
  console.log('всё сходится: подкидывают не больше, чем соперник может покрыть; в отбое только полные пары');
  process.exit(0);
} else {
  console.log('НАЙДЕНЫ НАРУШЕНИЯ:');
  беды.forEach(б => console.log('  - ' + б));
  process.exit(1);
}
