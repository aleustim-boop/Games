/* Проверяет, нет ли ключа на любой глубине вложенности */
function нетКлючаНиГде(объект, ключ, путь) {
  путь = путь || '';
  if (объект === null || объект === undefined) return true;

  if (typeof объект === 'object') {
    if (Array.isArray(объект)) {
      for (let i = 0; i < объект.length; i++) {
        const новыйПуть = путь + '[' + i + ']';
        if (объект[i] !== null && typeof объект[i] === 'object' && ключ in объект[i]) {
          console.log('      найден участники в ' + новыйПуть);
          return false;
        }
        if (!нетКлючаНиГде(объект[i], ключ, новыйПуть)) return false;
      }
    } else {
      for (const к in объект) {
        if (к === ключ) {
          console.log('      найден ключ ' + ключ + ' в ' + путь + '.' + к);
          return false;
        }
        const новыйПуть = путь ? путь + '.' + к : к;
        if (объект[к] !== null && typeof объект[к] === 'object') {
          if (!нетКлючаНиГде(объект[к], ключ, новыйПуть)) return false;
        }
      }
    }
  }
  return true;
}

/* Подпись Telegram */
function подписать(поля) {
  const строки = Object.keys(поля).map(function (к) { return к + '=' + поля[к]; }).sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(ТОКЕН).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}

function подпись(номер, имя) {
  const поля = {
    query_id: 'AAZ' + номер,
    user: JSON.stringify({ id: номер, first_name: имя }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  поля.hash = подписать(поля);
  return Object.keys(поля)
    .map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(поля[к]); })
    .join('&');
}

/* Разговор с дверями */
function спросить(путь, тело) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: АДРЕС, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (сбой) { разобрано = null; }
        готово({ код: ответ.statusCode, тело: разобрано || {}, текст: текст });
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

async function создатьСтол(кто, имя, мест) {
  const ответ = await спросить('/создать', {
    initData: подпись(кто, имя), имя: имя, метка: 'metka-участники-' + кто, игра: 'дурак', мест: мест
  });
  if (ответ.код !== 200 || !ответ.тело.код) throw new Error('стол для ' + имя + ' не создан: ' + ответ.текст);
  return { код: ответ.тело.код, пропуск: ответ.тело.пропуск, кто: кто, имя: имя, мест: мест || 2 };
}

async function войтиВторым(стол, кто, имя) {
  const ответ = await спросить('/войти', {
    код: стол.код, имя: имя, метка: 'metka-участники-' + кто, initData: подпись(кто, имя)
  });
  if (ответ.код !== 200) throw new Error('второй игрок не вошёл: ' + ответ.текст);
  return { пропуск: ответ.тело.пропуск, кто: кто, имя: имя };
}

async function видИгрока(стол, игрок) {
  const ответ = await спросить('/что-нового', { код: стол.код, пропуск: игрок.пропуск, версия: 0 });
  if (ответ.код !== 200) throw new Error('не получили состояние ' + игрок.имя + ': ' + ответ.текст);
  return ответ.тело;
}

