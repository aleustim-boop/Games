async function проверитьПятьСекундИПилюлю() {
  const п = партияДоПобеды();
  const П3 = 'Осталось 3 минуты — потом считаются очки';
  // 5 с: плашка держится и гаснет сама.
  let м = мир();
  м.мост.показатьВид(видЧасов(п, 1, 170000, 'С1'));
  проверка('5 с: плашка поставлена (ноль — провал)', м.пилюля() === П3, м.пилюля());
  м.часы.прошло(4500);
  проверка('5 с: через 4,5 с плашка ещё держится', м.пилюля() === П3, м.пилюля());
  м.часы.прошло(600);
  проверка('5 с: через 5,1 с плашка погасла сама', м.пилюля() === '', м.пилюля());
  // Пустая пилюля нового раунда плашку часов не гасит, пока 5 с не прошли.
  м = мир();
  const в1 = видЧасов(п, 1, 170000, 'С2');
  м.мост.показатьВид(в1);
  const в2 = видСледующегоРаунда(в1);
  в2.захват.мсДоКонцаПартии = 169000;
  м.мост.показатьВид(в2);
  проверка('5 с: новый раунд без своей плашки не гасит плашку часов', м.пилюля() === П3, м.пилюля());
  м.часы.прошло(5100);
  проверка('5 с: и она гаснет по своему таймеру', м.пилюля() === '', м.пилюля());
  // Другая плашка вытесняет часовую, её таймер не гасит чужое.
  м = мир();
  м.мост.показатьВид(видЧасов(п, 1, 170000, 'С3'));
  м.часы.прошло(3000);
  м.мост.показатьВид(видЧасов(п, 2, 50000, 'С3'));
  проверка('5 с: следующий порог (1 минута) заменяет плашку', м.пилюля().indexOf('1 минута') !== -1, м.пилюля());
  м.часы.прошло(3000);
  проверка('5 с: у новой плашки свои 5 с (прошло 3 с — держится)', м.пилюля().indexOf('1 минута') !== -1, м.пилюля());
  // Пилюля «Раунд уже разыгран» ждёт — плашку часов в этом показе не ставим.
  м = мир();
  const а = партияДоПобеды();
  const в = видЧасов(а, 1, 400000, 'С4');
  м.мост.показатьВид(в);
  м.сеть.ответЧерновика = { принято: false, причина: 'Раунд уже разыгран', устарел: true };
  м.модуль.стол().поставитьВойска(мояОбласть(в), 1);
  м.часы.прошло(м.Правила.ЧИСЛА.задержкаЧерновикаМс);
  await отпустить();
  const вТот = видЧасов(а, 2, 170000, 'С4');
  вТот.захват.раунд = в.захват.раунд;
  м.мост.показатьВид(вТот);
  проверка('пилюля ждёт: плашку часов в этом показе не ставим (ноль — провал)', м.пилюля() === '', м.пилюля());
  м.часы.прошло(1000);
  проверка('пилюля ждёт: следующий тик ставит плашку часов', м.пилюля() === П3, м.пилюля());
}

