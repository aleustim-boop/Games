  const первый = последнийВызов(с);
  проверить(с.вызовыЛиста.length === 1, 'поле пришло — лист позван один раз (' + с.вызовыЛиста.length + ')');
  проверить(Boolean(первый && первый.тексты && первый.тексты.строка.видна === true),
    'лист получил тексты: строка видна');
