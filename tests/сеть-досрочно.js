const СЕЙЧАС = 1700000000000;
function место(номер) { return МЕСТА[номер - 1]; }

/**
 * Поле «досрочно» так, как его соберёт сервер для игрока «я».
 *   что.идёт, что.предложил (номер места или null), что.имя,
 *   что.за / что.против / что.голосуют — списки номеров мест (голосуют — 1,2,3),
 *   что.я — мой номер (1), что.секунд, что.почему, что.порог (как у комнаты — 70 %).
 */
function поле(что) {
  что = что || {};
  const голосуют = что.голосуют || [1, 2, 3];
  const сырое = {
    голосование: что.идёт ? {
      кто: что.предложил ? место(что.предложил) : null,
      за: new Set((что.за || []).map(место)),
      против: new Set((что.против || []).map(место)),
      докуда: СЕЙЧАС + (что.секунд || 0) * 1000
    } : null,
    голосующие: голосуют.map(место),
    порог: что.порог !== undefined ? что.порог : Math.ceil(голосуют.length * 7 / 10),
    имяПредложившего: что.имя,
    почему: что.почему || null
  };
  return СЕРВЕР.досрочноДляИгрока(сырое, место(что.я || 1), СЕЙЧАС);
}

