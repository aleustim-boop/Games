// Ломающие запуски делает сама: портит КОПИЮ стола во временной папке и требует, чтобы проверка на ней покраснела.
// Свой поддельный документ: настоящая разметка захват.html, ширины задаёт проверка (по 10 точек на букву).
'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const КОРЕНЬ = path.resolve(__dirname, '..');
const аргументы = process.argv.slice(2);
const индексФайла = аргументы.indexOf('--файл');
const путьСтола = индексФайла === -1 ? path.join(КОРЕНЬ, 'js', 'захват-стол.js') : аргументы[индексФайла + 1];

const Правила = require(path.join(КОРЕНЬ, 'js', 'захват-правила.js'));
const ЗахватСтол = require(путьСтола);

let пройдено = 0;
let провалов = 0;
function проверка(название, условие, подробность) {
  if (условие) { пройдено++; return; }
  провалов++;
  console.log('ПРОВАЛ: ' + название + (подробность ? ' — ' + подробность : ''));
}

// ---------- поддельный документ ----------

const ТОЧЕК_НА_БУКВУ = 10;
const ЗАЗОР = 8;
let ширинаКапсулы = 0;   // 0 — замера нет

class Узел {
  constructor(тег, атрибуты) {
    this.тег = тег;
    this.атрибуты = атрибуты || {};
    this.дети = [];
    this.parentNode = null;
    this._текст = '';
    this.value = '';
    const сам = this;
    this.style = { setProperty() {} };
    this.classList = {
      add(имя) { const с = сам.классы(); if (с.indexOf(имя) === -1) с.push(имя); сам.атрибуты.class = с.join(' '); },
      remove(имя) { сам.атрибуты.class = сам.классы().filter(function (к) { return к !== имя; }).join(' '); },
      contains(имя) { return сам.классы().indexOf(имя) !== -1; }
    };
  }
  классы() { return (this.атрибуты.class || '').split(/\s+/).filter(Boolean); }
  get children() { return this.дети; }
  get nextSibling() {
    if (!this.parentNode) return null;
    const д = this.parentNode.дети;
    return д[д.indexOf(this) + 1] || null;
  }
  get textContent() { return this.дети.length ? this.дети.map(function (д) { return д.textContent; }).join('') : this._текст; }
  set textContent(значение) { this.дети = []; this._текст = String(значение); }
  setAttribute(имя, значение) { this.атрибуты[имя] = String(значение); }
  getAttribute(имя) { return имя in this.атрибуты ? this.атрибуты[имя] : null; }
  removeAttribute(имя) { delete this.атрибуты[имя]; }
  appendChild(ребёнок) { ребёнок.parentNode = this; this.дети.push(ребёнок); return ребёнок; }
  insertBefore(новый, перед) {
    новый.parentNode = this;
    const и = перед ? this.дети.indexOf(перед) : -1;
    if (и === -1) this.дети.push(новый); else this.дети.splice(и, 0, новый);
    return новый;
  }
  replaceChildren() { this.дети = []; this._текст = ''; }
  addEventListener() {}
  getBoundingClientRect() { return { left: 0, top: 0 }; }
  // Замеры капсулы: раунд и часы сами не обрезаются, капсула суммирует видимое содержимое.
  get clientWidth() { return this.классы().indexOf('захват-раунд') !== -1 ? ширинаКапсулы : 0; }
  get scrollWidth() {
    if (this.классы().indexOf('захват-раунд') === -1) return 0;
    const видимые = this.дети.filter(function (д) { return д.классы().indexOf('скрыт') === -1 && д.textContent; });
    const буквы = видимые.reduce(function (с, д) { return с + Array.from(д.textContent).length; }, 0);
    return буквы * ТОЧЕК_НА_БУКВУ + ЗАЗОР * Math.max(0, видимые.length - 1);
  }
  querySelector(селектор) {
    const имя = селектор.replace(/^\./, '');
    return всеУзлы(this).filter(function (у) { return у !== this && у.classList.contains(имя); }, this)[0] || null;
  }
}

function всеУзлы(корень) {
  const итог = [корень];
  корень.дети.forEach(function (д) { всеУзлы(д).forEach(function (у) { итог.push(у); }); });
  return итог;
}

function разобратьРазметку(текст) {
  const без = ['input', 'br', 'img'];
  const корень = new Узел('корень', {});
  let текущий = корень;
  const шаблон = /<!--[\s\S]*?-->|<\/(\w+)\s*>|<(\w+)((?:\s+[^\s=>\/]+(?:\s*=\s*(?:"[^"]*"|'[^']*'|[^\s>]+))?)*)\s*\/?>|([^<]+)/g;
  let м;
  while ((м = шаблон.exec(текст)) !== null) {
    if (м[1]) {
      if (текущий.parentNode) текущий = текущий.parentNode;
    } else if (м[2]) {
      const атрибуты = {};
      const разбор = /([^\s=]+)(?:\s*=\s*"([^"]*)")?/g;
      let а;
      while ((а = разбор.exec(м[3] || '')) !== null) атрибуты[а[1]] = а[2] === undefined ? '' : а[2];
      const узел = new Узел(м[2], атрибуты);
      текущий.appendChild(узел);
      if (без.indexOf(м[2]) === -1) текущий = узел;
    } else if (м[4] && м[4].trim()) {
      if (!текущий.дети.length) текущий._текст += м[4].replace(/\s+/g, ' ').trim();
    }
  }
  return корень;
}

function сделатьДокумент() {
  const html = fs.readFileSync(path.join(КОРЕНЬ, 'захват.html'), 'utf8');
  const начало = html.indexOf('<section id="экран-игры"');
  const конец = html.indexOf('</section>', начало);
  if (начало === -1 || конец === -1) throw new Error('В захват.html нет раздела экран-игры');
  const корень = разобратьРазметку(html.slice(начало, конец + '</section>'.length));
  const поId = {};
  всеУзлы(корень).forEach(function (у) { if (у.атрибуты.id) поId[у.атрибуты.id] = у; });
  return {
    корень: корень,
    getElementById(id) { return поId[id] || null; },
    createElement(тег) { return new Узел(тег, {}); },
    defaultView: { getComputedStyle() { return { columnGap: 'normal', paddingBottom: '', getPropertyValue() { return ''; } }; } }
  };
}

// ---------- проверки ----------

function партияДоПобеды(раунд) {
  const п = Правила.новаяПартия({ игроки: ['a', 'b'], люди: ['a'], раундовЗахвата: 'победа' }, function () { return 0.5; });
  п.раунд = раунд;
  return п;
}

function новыйСтол(партия, онлайн) {
  const документ = сделатьДокумент();
  const стол = ЗахватСтол.создать({ документ: документ });
  стол.начатьРаунд(партия, 'a', { имена: { a: 'Вы', b: 'Бот' } });
  const таймер = документ.getElementById('захват-таймер');
  if (онлайн) { таймер.textContent = '0:42'; таймер.classList.remove('скрыт'); }
  return { стол, документ };
}

function раундУ(с) { return с.документ.getElementById('захват-раунд').textContent; }

// Узел часов стол создаёт сам рядом с таймером: ищем его в капсуле, не в разметке.
function часыУ(с) {
  const капсула = с.документ.getElementById('захват-раунд').parentNode;
  return всеУзлы(капсула).filter(function (н) { return н.атрибуты.id === 'захват-часы'; })[0] || null;
}

function прогнать() {
  ширинаКапсулы = 0;
  проверка('сама проверка видит число начальных проверок (не ноль)', typeof ЗахватСтол.создать === 'function');

  [1, 7, 41, 91, 99].forEach(function (н) {
    const с = новыйСтол(партияДоПобеды(н), false);
    проверка('«До победы»: на раунде ' + н + ' в капсуле «Раунд ' + н + '» без «из»', раундУ(с) === 'Раунд ' + н, раундУ(с));
  });

  const с = новыйСтол(партияДоПобеды(7), false);
  const слова = function (мс) { с.стол.показатьЧасы(мс); const ч = часыУ(с); return ч ? ч.textContent : null; };
  проверка('380000 мс → «ещё 6:20»', слова(380000) === '· ещё 6:20', слова(380000));
  проверка('379400 мс (6:19,4) → «ещё 6:20», секунды вверх', слова(379400) === '· ещё 6:20', слова(379400));
  проверка('600000 мс → «ещё 10:00»', слова(600000) === '· ещё 10:00', слова(600000));
  проверка('59001 мс → «ещё 1:00»', слова(59001) === '· ещё 1:00', слова(59001));
  проверка('0 → «последний раунд»', слова(0) === '· последний раунд', слова(0));
  проверка('часы не мигают: класса «--мало» у них нет', !/мало/.test(часыУ(с).атрибуты.class || ''), часыУ(с).атрибуты.class);
  с.стол.показатьЧасы(null);
  проверка('null → узел часов скрыт и пуст', !!часыУ(с) && часыУ(с).classList.contains('скрыт') && часыУ(с).textContent === '');
  с.стол.показатьЧасы(100000);
  проверка('после null часы снова показываются', !часыУ(с).classList.contains('скрыт'));
  с.стол.задатьКонец(true);
  проверка('партия кончилась: «Раунд 7 · конец», часы скрыты', раундУ(с) === 'Раунд 7 · конец' && часыУ(с).classList.contains('скрыт'), раундУ(с));

  const обычная = Правила.новаяПартия({ игроки: ['a', 'b'], люди: ['a'] }, function () { return 0.5; });
  const о = новыйСтол(обычная, false);
  о.стол.показатьЧасы(380000);
  проверка('обычная партия: «из N» есть, часов нет', /^Раунд \d+ из \d+$/.test(раундУ(о)) && часыУ(о).classList.contains('скрыт'), раундУ(о));

  // Лесенка «не влезает»: ширину капсулы задаём, буква = 10 точек, зазор 8.
  const ступень = function (онлайн, мс, ширина) {
    const ст = новыйСтол(партияДоПобеды(7), онлайн);
    ширинаКапсулы = ширина;
    ст.стол.показатьЧасы(мс);
    ширинаКапсулы = 0;
    return часыУ(ст).textContent;
  };
  проверка('с ботами, широко: полный «· ещё 6:20»', ступень(false, 380000, 400) === '· ещё 6:20', ступень(false, 380000, 400));
  проверка('с ботами, узко: «· 6:20»', ступень(false, 380000, 165) === '· 6:20', ступень(false, 380000, 165));
  проверка('с ботами, конец, широко: «· последний раунд»', ступень(false, 0, 400) === '· последний раунд');
  проверка('с ботами, конец, узко: «· последний»', ступень(false, 0, 200) === '· последний', ступень(false, 0, 200));
  проверка('онлайн считает и таймер раунда: на 190 «· 6:20», а с ботами на 190 — полный',
    ступень(true, 380000, 190) === '· 6:20' && ступень(false, 380000, 190) === '· ещё 6:20',
    ступень(true, 380000, 190) + ' / ' + ступень(false, 380000, 190));
  проверка('ничего не влезло — остаётся самый короткий', ступень(false, 0, 50) === '· последний');
}

// ---------- ломающие запуски на копии ----------

function ломающий(название, изменить) {
  const исходник = fs.readFileSync(путьСтола, 'utf8');
  const испорчен = изменить(исходник);
  if (испорчен === исходник) {
    провалов++;
    console.log('ПРОВАЛ: ломающий запуск «' + название + '» ничего не испортил — не нашёл, что ломать');
    return;
  }
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-часы-'));
  fs.mkdirSync(path.join(папка, 'js'));
  fs.readdirSync(path.join(КОРЕНЬ, 'js')).forEach(function (имя) {
    if (/\.js$/.test(имя)) fs.copyFileSync(path.join(КОРЕНЬ, 'js', имя), path.join(папка, 'js', имя));
  });
  const копия = path.join(папка, 'js', 'захват-стол.js');
  fs.writeFileSync(копия, испорчен);
  const итог = spawnSync(process.execPath, [__filename, '--файл', копия], { encoding: 'utf8' });
  проверка('ломающий запуск «' + название + '»: проверка краснеет', итог.status === 1, 'код выхода ' + итог.status);
}

прогнать();
if (индексФайла === -1) {
  ломающий('копия со старым «безПредела» (на 91-м появляется «из 100»)', function (т) {
    return т.replace("(п.доПобеды ? '' : ' из '", "((!!п.доПобеды && п.всегоРаундов - п.раунд >= 10) ? '' : ' из '");
  });
  ломающий('копия с округлением секунд вниз', function (т) { return т.replace('Math.ceil(Math.max(0, мс) / 1000)', 'Math.floor(Math.max(0, мс) / 1000)'); });
  ломающий('копия без проверки ширины капсулы', function (т) { return т.replace('if (!(капсула.clientWidth > 0)) return true;', 'return true;'); });
  ломающий('копия, где замер не учитывает капсулу целиком (таймер раунда)', function (т) {
    return т.replace('return !лишний(капсула) && !лишний(раунд) && !лишний(часы);', 'return !лишний(раунд) && !лишний(часы);');
  });
  ломающий('копия, где часы остаются после конца партии', function (т) { return т.replace('!состояние.конец && состояние.часыМс', 'состояние.часыМс'); });
}

