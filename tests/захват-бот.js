function прогнать(файл) {
  const текст = fs.readFileSync(файл, 'utf8');
  проверитьТекст(текст);
  let Б;
  let песочница;
  try {
    Б = загрузитьКакМодуль(текст);
    песочница = собратьПесочницу(текст);
  } catch (ошибка) {
    проверить(false, 'файл загружается без ошибок (' + ошибка.message + ')');
    return;
  }
  проверить(!!песочница.ЗахватБот, 'в браузере файл отдаёт window.ЗахватБот');
  проверить(typeof Б.решить === 'function' && typeof Б.задержкаСекунд === 'function', 'наружу есть решить и задержкаСекунд');
  let отказ = '';
  try { Б.решить(партия27(), 'X', 'невиданный', постоянный(0.5)); } catch (ошибка) { отказ = ошибка.message; }
  проверить(/уровня/.test(отказ), 'неизвестный уровень — ошибка, а не молчаливый выбор (вышло «' + отказ + '»)');

  проверить(СЛУЧАИ.length >= 5, 'случаев в списке ' + СЛУЧАИ.length + ' (ноль найденного — провал)');
  СЛУЧАИ.forEach((с) => {
    const было = провалов;
    try {
      с.проверка(Б);
    } catch (ошибка) {
      проверить(false, 'случай ' + с.номер + ' упал: ' + ошибка.message);
    }
    console.log((провалов === было ? '  ок   — ' : '  ПЛОХО— ') + 'случай ' + с.номер + ': ' + с.имя);
  });

  const было = провалов;
  try {
    проверитьЗёрна(Б, песочница);
  } catch (ошибка) {
    проверить(false, '1000 зёрен: прогон упал: ' + ошибка.message);
  }
  console.log((провалов === было ? '  ок   — ' : '  ПЛОХО— ') + '1000 зёрен: обе карты, все места, три уровня');

  // Полные партии ботов до конца — отдельным этапом после А3–А4 (разбор раунда и конец партии).
  // Здесь — только короткий прогон нескольких раундов, если разбор уже есть в правилах.
  if (typeof П.разобратьРаунд !== 'function') {
    console.log('  заметка: разобратьРаунд в правилах ещё нет — раунды ботов здесь не гоняются');
    return;
  }
  const доРаундов = провалов;
  try {
    прогнатьРаунды(Б);
  } catch (ошибка) {
    проверить(false, 'раунды ботов: прогон упал: ' + ошибка.message);
  }
  console.log((провалов === доРаундов ? '  ок   — ' : '  ПЛОХО— ') + 'короткий прогон: 50 столов ботов по 5 раундов через разобратьРаунд');
}

// Боты за всеми местами (уровни по кругу) играют 5 раундов подряд: каждый черновик принят,
// разбор не падает, номер раунда растёт. До конца партии не доходим — это этап после А4.
function прогнатьРаунды(Б) {
  let раундов = 0;
  let отказов = 0;
  let первый = '';
  for (let зерно = 1; зерно <= 50; зерно++) {
    let п = позиция(зерно * 4);
    const сл = генератор(зерно + 100000);
    for (let круг = 0; круг < 5; круг++) {
      const черновики = {};
      п.игроки.forEach((место, и) => {
        const уровень = УРОВНИ[(и + зерно) % УРОВНИ.length];
        const ч = Б.решить(п, место, уровень, сл);
        const проверка = П.проверитьЧерновик(п, место, ч);
        if (!проверка.принято) {
          отказов++;
          if (!первый) первый = 'зерно ' + зерно + ', раунд ' + п.раунд + ', ' + место + ': ' + проверка.причина;
        }
        черновики[место] = ч;
      });
      const былРаунд = п.раунд;
      п = П.разобратьРаунд(п, черновики, сл).партия;
      проверить(п.раунд === былРаунд + 1, 'раунды ботов: после разбора номер раунда +1 (зерно ' + зерно + ')');
      раундов++;
    }
  }
  проверить(раундов === 250, 'раунды ботов: сыграно раундов ' + раундов + ', ждали 250');
  проверить(отказов === 0, 'раунды ботов: черновики приняты — отказов ' + отказов + (первый ? ' (первый: ' + первый + ')' : ''));
}

