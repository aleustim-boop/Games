// Позиция по зерну: обычная раздача; три четверти позиций «встряхнуты» — случайные хозяева,
// войска и раунд, чтобы бот видел и середину партии, и выбывших; каждая десятая — первая партия новичка.
function позиция(зерно) {
  const сл = генератор(зерно);
  if (зерно % 10 === 3) {
    const п = П.новаяПартия({ игроки: ['б1', 'я', 'б2'], новичок: 'я', люди: ['я'] }, сл);
    п.новичок = 'я';
    return п;
  }
  const мест = 2 + (зерно % 5);
  const игроки = Array.from({ length: мест }, (_, и) => 'м' + (и + 1));
  const п = П.новаяПартия({ игроки: игроки }, сл);
  if (зерно % 4 === 0) return п;
  п.раунд = 1 + Math.floor(сл() * п.всегоРаундов);
  for (let н = 1; н < п.хозяева.length; н++) {
    if (сл() < 0.4) {
      const в = Math.floor(сл() * (игроки.length + 1));
      п.хозяева[н] = в === игроки.length ? null : игроки[в];
    }
    п.войска[н] = 1 + Math.floor(сл() * 15);
  }
  игроки.forEach((к) => { п.подкрепление[к] = П.подкрепление(п, к).всего; });
  return п;
}

function прогнатьЗёрна(Б, песочница) {
  const итог = {
    решений: 0, ошибок: [], долгих: [], отказов: [], недоставлено: [], лишнихУдаров: [],
    кривыхЦелей: [], переводовЛёгкого: [], разнобой: [], правок: [],
    карты: new Set(), мест: new Set(), ударов: { лёгкий: 0, обычный: 0, сложный: 0 },
    переводов: { лёгкий: 0, обычный: 0, сложный: 0 }, дольшеВсегоМс: 0
  };
  function запомнить(список, текст) {
    if (список.length < 3) список.push(текст);
    else список.push(null);
  }
  for (let зерно = 1; зерно <= ЗЁРЕН; зерно++) {
    const п = позиция(зерно);
    const партияJSON = JSON.stringify(п);
    итог.карты.add(п.карта);
    итог.мест.add(п.игроки.length);
    п.игроки.forEach((место) => УРОВНИ.forEach((уровень) => {
      const где = 'зерно ' + зерно + ', ' + п.карта + ', ' + место + ', ' + уровень;
      const р = решитьСПределом(песочница, партияJSON, место, уровень, зерно);
      итог.решений++;
      if (р.ошибка) { запомнить(итог.ошибок, где + ': ' + р.ошибка); return; }
      итог.дольшеВсегоМс = Math.max(итог.дольшеВсегоМс, р.мс);
      if (р.мс > ПРЕДЕЛ_РЕШЕНИЯ_МС) запомнить(итог.долгих, где + ': ' + Math.round(р.мс) + ' мс');
      const ч = р.черновик;
      const проверка = П.проверитьЧерновик(п, место, ч);
      if (!проверка.принято) запомнить(итог.отказов, где + ': «' + проверка.причина + '» ' + кратко(ч));
      const поставлено = Object.keys(ч.расстановка).reduce((с, к) => с + ч.расстановка[к], 0);
      const естьОбласти = п.хозяева.some((х) => х === место);
      const ждём = естьОбласти ? (п.подкрепление[место] || 0) : 0;
      if (поставлено !== ждём) запомнить(итог.недоставлено, где + ': поставлено ' + поставлено + ' из ' + ждём);
      const удары = ч.приказы.filter((пр) => п.хозяева[пр.в] !== место);
      const переводы = ч.приказы.length - удары.length;
      итог.ударов[уровень] += удары.length;
      итог.переводов[уровень] += переводы;
      if (удары.length > УДАРОВ_НЕ_БОЛЬШЕ[уровень]) запомнить(итог.лишнихУдаров, где + ': ударов ' + удары.length);
      if (new Set(удары.map((пр) => пр.в)).size !== удары.length) запомнить(итог.кривыхЦелей, где + ': в одну цель из двух областей');
      if (уровень === 'лёгкий' && переводы) запомнить(итог.переводовЛёгкого, где + ': переводов ' + переводы);
      // Каждое 50-е зерно: дорога require даёт то же самое и партию не меняет.
      if (зерно % 50 === 0) {
        const копия = JSON.parse(партияJSON);
        const ч2 = Б.решить(копия, место, уровень, генератор(зерно));
        if (кратко(ч2) !== кратко(ч)) запомнить(итог.разнобой, где + ': ' + кратко(ч2) + ' против ' + кратко(ч));
        if (JSON.stringify(копия) !== партияJSON) запомнить(итог.правок, где);
      }
    }));
  }
  return итог;
}

function описать(список) {
  const видно = список.filter(Boolean);
  return список.length + (видно.length ? ' (например: ' + видно.join('; ') + ')' : '');
}

