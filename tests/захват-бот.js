// Стол по зерну: 2–6 мест, карта по числу мест (2–3 — «остров», 4–6 — «материк»: так задано
// в составах правил, на другой карте нет гнёзд столиц), уровни по кругу со сдвигом по зерну.
function сыгратьПартию(Б, зерно, раундовЗахвата) {
  const мест = 2 + (зерно % 5);
  const игроки = Array.from({ length: мест }, (_, и) => 'м' + (и + 1));
  const сл = генератор(зерно * 7919 + 13);
  const настройки = { игроки: игроки };
  if (раундовЗахвата) настройки.раундовЗахвата = раундовЗахвата;
  let п = П.новаяПартия(настройки, сл);
  const предел = п.всегоРаундов;
  const начало = process.hrtime.bigint();
  const результат = { зерно: зерно, карта: п.карта, мест: мест, раундов: 0, ошибка: null, отказов: [], не_кончилась: false, мс: 0 };
  while (!п.завершена) {
    if (результат.раундов >= предел) { результат.не_кончилась = true; break; }
    if (Number(process.hrtime.bigint() - начало) / 1e6 > ПРЕДЕЛ_ПАРТИИ_МС) { результат.ошибка = 'партия идёт дольше ' + ПРЕДЕЛ_ПАРТИИ_МС + ' мс (зависание)'; break; }
    const черновики = {};
    try {
      игроки.forEach((место, и) => {
        const уровень = УРОВНИ[(и + зерно) % УРОВНИ.length];
        const ч = Б.решить(п, место, уровень, сл);
        const проверка = П.проверитьЧерновик(п, место, ч);
        if (!проверка.принято) результат.отказов.push('раунд ' + п.раунд + ', ' + место + ': ' + проверка.причина);
        черновики[место] = ч;
      });
      п = П.разобратьРаунд(п, черновики, сл).партия;
    } catch (ошибка) {
      результат.ошибка = ошибка.message;
      break;
    }
    результат.раундов++;
  }
  результат.мс = Number(process.hrtime.bigint() - начало) / 1e6;
  результат.партия = п;
  результат.предел = предел;
  return результат;
}

function проверитьИтогПартии(п) {
  const и = П.итог(п);
  const беда = [];
  if (!и.завершена) беда.push('итог говорит «не завершена»');
  if (typeof и.результат !== 'string' || !п.игроки.includes(и.результат)) беда.push('победитель — не одно место: ' + JSON.stringify(и.результат));
  if (и.ничья !== false) беда.push('ничья не false');
  const места = и.итог ? и.итог.места.map((м) => м.кто) : [];
  const все = new Set(места);
  if (места.length !== п.игроки.length || все.size !== места.length || !п.игроки.every((к) => все.has(к))) {
    беда.push('места — не перестановка всех мест: ' + места.join(','));
  }
  if (места[0] !== и.результат) беда.push('победитель не первый в местах');
  if (!и.итог || !и.итог.причина) беда.push('нет причины конца');
  // Победители (ТЗ 5): непусты, все живые, их не больше половины мест; проигравшие — все остальные.
  const победители = и.победители || [];
  const половина = Math.floor(п.игроки.length / 2);
  if (!победители.length) беда.push('победителей нет');
  if (победители.length > половина) беда.push('победителей ' + победители.length + ' больше половины мест (' + половина + ')');
  const строки = и.итог ? и.итог.места : [];
  победители.forEach((к) => {
    const м = строки.find((с) => с.кто === к);
    if (!м || м.как !== 'живой') беда.push('победитель ' + к + ' не живой (' + (м ? м.как : 'нет в местах') + ')');
  });
  if (победители[0] !== и.результат) беда.push('результат не первый среди победителей');
  if (JSON.stringify(п.победители) !== JSON.stringify(победители)) беда.push('партия.победители не совпадает с итогом');
  const ждутПроигравшими = п.игроки.filter((к) => !победители.includes(к));
  if (JSON.stringify(и.проигравшие) !== JSON.stringify(ждутПроигравшими) || и.проигравшие.some((к) => победители.includes(к))) {
    беда.push('проигравшие — не «все места минус победители»');
  }
  return беда;
}

// А5д: длина партии — выбор стола. По ПАРТИЙ_НА_ДЛИНУ партий на 10 и на 20 раундов (обе карты:
// карта идёт по числу мест, как в обычных партиях); обычная — 15, первая партия новичка — 10.
function проверитьДлиныПартий(Б) {
  const общее = process.hrtime.bigint();
  const обычная = П.новаяПартия({ игроки: ['м1', 'м2', 'м3'] }, генератор(5));
  проверить(обычная.всегоРаундов === 15, 'длина: у обычной партии 15 раундов, вышло ' + обычная.всегоРаундов);
  const новичок = П.новаяПартия({ игроки: ['б1', 'я', 'б2'], новичок: 'я', люди: ['я'] }, генератор(6));
  проверить(новичок.всегоРаундов === 10, 'длина: у новичка 10 раундов, вышло ' + новичок.всегоРаундов);
  [10, 20].forEach((длина) => {
    const ошибок = [], незаконченных = [], отказов = [], кривых = [], лишних = [], недобор = [];
    const карты = new Set();
    let по_раундам = 0;
    let сыграно = 0;
    for (let зерно = 1; зерно <= ПАРТИЙ_НА_ДЛИНУ; зерно++) {
      const р = сыгратьПартию(Б, зерно + 50000 * длина, длина);
      сыграно++;
      карты.add(р.карта);
      const где = 'на ' + длина + ', зерно ' + зерно + ' (' + р.карта + ', ' + р.мест + ' мест)';
      if (р.партия.всегоРаундов !== длина) { кривых.push(где + ': всегоРаундов ' + р.партия.всегоРаундов); continue; }
      if (р.ошибка) { ошибок.push(где + ': ' + р.ошибка); continue; }
      if (р.не_кончилась) { незаконченных.push(где + ': не кончилась за ' + р.предел + ' раундов'); continue; }
      if (р.отказов.length) отказов.push(где + ': ' + р.отказов[0]);
      if (р.раундов > длина) лишних.push(где + ': сыграно ' + р.раундов);
      if (р.партия.конец && р.партия.конец.причина === 'раунды') {
        по_раундам++;
        if (р.раундов !== длина) недобор.push(где + ': кончилась по раундам, сыграно ' + р.раундов + ', выбрано ' + длина);
      }
      const беда = проверитьИтогПартии(р.партия);
      if (беда.length) кривых.push(где + ': ' + беда.join('; '));
    }
    const показ = (с) => с.length + (с.length ? ' (например: ' + с.slice(0, 3).join('; ') + ')' : '');
    проверить(сыграно === ПАРТИЙ_НА_ДЛИНУ, 'на ' + длина + ': сыграно ' + сыграно + ' партий (ноль найденного — провал)');
    проверить(карты.has('остров') && карты.has('материк'), 'на ' + длина + ': обе карты (' + [...карты].join(', ') + ')');
    проверить(по_раундам > 0, 'на ' + длина + ': есть партии, кончившиеся по раундам (' + по_раундам + ') — иначе проверка пустая');
    проверить(ошибок.length === 0, 'на ' + длина + ': без ошибок и зависаний — ' + показ(ошибок));
    проверить(незаконченных.length === 0, 'на ' + длина + ': каждая доходит до «завершена» — ' + показ(незаконченных));
    проверить(отказов.length === 0, 'на ' + длина + ': черновики ботов приняты — ' + показ(отказов));
    проверить(лишних.length === 0, 'на ' + длина + ': раундов сыграно не больше выбранного — ' + показ(лишних));
    проверить(недобор.length === 0, 'на ' + длина + ': кончившаяся по раундам сыграна ровно ' + длина + ' — ' + показ(недобор));
    проверить(кривых.length === 0, 'на ' + длина + ': всегоРаундов равен выбору, итог верный (победители живые, непусты) — ' + показ(кривых));
    console.log('         на ' + длина + ' раундов: партий ' + сыграно + ', кончились по раундам ' + по_раундам);
  });
  console.log('         длины партий за ' + (Number(process.hrtime.bigint() - общее) / 1e9).toFixed(1) + ' с');
}

function проверитьПолныеПартии(Б) {
  const общее = process.hrtime.bigint();
  const причины = {};
  const раундовНаКартах = {};
  const ошибок = [], незаконченных = [], отказов = [], кривыхИтогов = [], долгих = [];
  let сыграно = 0;
  let уложились = true;
  const карты = new Set(), мест = new Set();
  for (let зерно = 1; зерно <= ПАРТИЙ_ДО_КОНЦА; зерно++) {
    if (Number(process.hrtime.bigint() - общее) / 1e6 > ПРЕДЕЛ_ВСЕХ_ПАРТИЙ_МС) { уложились = false; break; }
    const р = сыгратьПартию(Б, зерно);
    сыграно++;
    карты.add(р.карта); мест.add(р.мест);
    раундовНаКартах[р.карта] = раундовНаКартах[р.карта] || { партий: 0, раундов: 0, предел: 0 };
    раундовНаКартах[р.карта].предел += р.предел;
    раундовНаКартах[р.карта].партий++;
    раундовНаКартах[р.карта].раундов += р.раундов;
    const где = 'зерно ' + зерно + ' (' + р.карта + ', ' + р.мест + ' мест)';
    if (р.ошибка) { ошибок.push(где + ': ' + р.ошибка); continue; }
    if (р.не_кончилась) { незаконченных.push(где + ': не кончилась за ' + р.предел + ' раундов'); continue; }
    if (р.мс > ПРЕДЕЛ_ПАРТИИ_МС) долгих.push(где + ': ' + Math.round(р.мс) + ' мс');
    if (р.отказов.length) отказов.push(где + ': ' + р.отказов[0] + ' (всего ' + р.отказов.length + ')');
    const беда = проверитьИтогПартии(р.партия);
    if (беда.length) кривыхИтогов.push(где + ': ' + беда.join('; '));
    const пр = р.партия.конец ? р.партия.конец.причина : '?';
    причины[пр] = (причины[пр] || 0) + 1;
  }
  const секунд = Number(process.hrtime.bigint() - общее) / 1e9;
  const показ = (с) => с.length + (с.length ? ' (например: ' + с.slice(0, 3).join('; ') + ')' : '');
  проверить(сыграно >= 100, 'до конца: сыграно партий ' + сыграно + ' (ноль найденного — провал)');
  проверить(уложились, 'до конца: весь прогон не дольше ' + ПРЕДЕЛ_ВСЕХ_ПАРТИЙ_МС / 1000 + ' с — успели ' + сыграно + ' партий из ' + ПАРТИЙ_ДО_КОНЦА);
  проверить(карты.has('остров') && карты.has('материк'), 'до конца: обе карты (' + [...карты].join(', ') + ')');
  проверить([2, 3, 4, 5, 6].every((м) => мест.has(м)), 'до конца: столы на 2–6 мест');
  проверить(ошибок.length === 0, 'до конца: без ошибок и зависаний — ' + показ(ошибок));
  проверить(незаконченных.length === 0, 'до конца: каждая партия кончается не позже предела раундов — ' + показ(незаконченных));
  проверить(долгих.length === 0, 'до конца: партия не дольше ' + ПРЕДЕЛ_ПАРТИИ_МС + ' мс — ' + показ(долгих));
  проверить(отказов.length === 0, 'до конца: все черновики ботов приняты — ' + показ(отказов));
  проверить(кривыхИтогов.length === 0, 'до конца: итог — один победитель, ничья false, места без повторов — ' + показ(кривыхИтогов));
  const среднее = Object.keys(раундовНаКартах).map((к) => к + ' ' + (раундовНаКартах[к].раундов / раундовНаКартах[к].партий).toFixed(1) +
    ' из ' + (раундовНаКартах[к].предел / раундовНаКартах[к].партий).toFixed(1)).join(', ');
  console.log('         полных партий ' + сыграно + ' за ' + секунд.toFixed(1) + ' с; раундов в среднем: ' + среднее +
    '; чем кончились: ' + JSON.stringify(причины));
}

