function собратьПесочницу(текст) {
  const окно = {};
  окно.window = окно;
  const песочница = vm.createContext(окно);
  vm.runInContext(fs.readFileSync(ФАЙЛ_КАРТ, 'utf8'), песочница, { filename: ФАЙЛ_КАРТ });
  vm.runInContext(fs.readFileSync(ФАЙЛ_ПРАВИЛ, 'utf8'), песочница, { filename: ФАЙЛ_ПРАВИЛ });
  vm.runInContext(текст, песочница, { filename: ФАЙЛ_БОТА });
  vm.runInContext(ТЕКСТ_ГЕНЕРАТОРА, песочница);
  return песочница;
}

