// Боты за всеми местами (уровни по кругу) играют до 5 раундов подряд: каждый черновик принят,
// разбор не падает. Стол прерывается, когда партия кончилась (честный конец бывает раньше —
// бот взял все столицы); раунды считаются по факту. После конца номер раунда не растёт,
// а разбор оконченной партии — ошибка.
function прогнатьРаунды(Б) {
  let раундов = 0;
  let отказов = 0;
  let первый = '';
  let окончено = 0;
  for (let зерно = 1; зерно <= 50; зерно++) {
    let п = позиция(зерно * 4);
    const сл = генератор(зерно + 100000);
    for (let круг = 0; круг < 5 && !п.завершена; круг++) {
      const черновики = {};
      п.игроки.forEach((место, и) => {
        const уровень = УРОВНИ[(и + зерно) % УРОВНИ.length];
        const ч = Б.решить(п, место, уровень, сл);
        const проверка = П.проверитьЧерновик(п, место, ч);
        if (!проверка.принято) {
          отказов++;
          if (!первый) первый = 'зерно ' + зерно + ', раунд ' + п.раунд + ', ' + место + ': ' + проверка.причина;
        }
        черновики[место] = ч;
      });
      const былРаунд = п.раунд;
      п = П.разобратьРаунд(п, черновики, сл).партия;
      if (п.завершена) {
        проверить(п.раунд === былРаунд, 'раунды ботов: при конце партии номер раунда не растёт (зерно ' + зерно + ': ' + былРаунд + ' → ' + п.раунд + ')');
      } else {
        проверить(п.раунд === былРаунд + 1, 'раунды ботов: после разбора номер раунда +1 (зерно ' + зерно + ')');
      }
      раундов++;
    }
    if (п.завершена) {
      окончено++;
      let текст = '';
      try { П.разобратьРаунд(п, {}, сл); } catch (ошибка) { текст = ошибка.message; }
      проверить(/Партия уже окончена/.test(текст), 'раунды ботов: разбор оконченной партии кидает «Партия уже окончена» (зерно ' + зерно + ', вышло «' + текст + '»)');
    }
  }
  проверить(раундов >= 50, 'раунды ботов: сыграно раундов ' + раундов + ' (ноль найденного — провал)');
  проверить(отказов === 0, 'раунды ботов: черновики приняты — отказов ' + отказов + (первый ? ' (первый: ' + первый + ')' : ''));
  console.log('         короткий прогон: раундов сыграно ' + раундов + ', столов, кончившихся раньше 5 раундов: ' + окончено);
}

