// Дорога браузера: песочница с window, карты и правила подключены раньше бота.
const ТЕКСТ_ГЕНЕРАТОРА =
  'function генератор(зерно) { let с = зерно >>> 0; return function () {' +
  ' с = (с + 0x6D2B79F5) >>> 0; let т = с; т = Math.imul(т ^ (т >>> 15), т | 1);' +
  ' т ^= т + Math.imul(т ^ (т >>> 7), т | 61); return ((т ^ (т >>> 14)) >>> 0) / 4294967296; }; }';

function собратьПесочницу(текст) {
  const окно = {};
  окно.window = окно;
  const песочница = vm.createContext(окно);
  vm.runInContext(fs.readFileSync(ФАЙЛ_КАРТ, 'utf8'), песочница, { filename: ФАЙЛ_КАРТ });
  vm.runInContext(fs.readFileSync(ФАЙЛ_ПРАВИЛ, 'utf8'), песочница, { filename: ФАЙЛ_ПРАВИЛ });
  vm.runInContext(текст, песочница, { filename: ФАЙЛ_БОТА });
  vm.runInContext(ТЕКСТ_ГЕНЕРАТОРА, песочница);
  return песочница;
}

// Тот же генератор для node-стороны (раскладка позиций): детерминированный по зерну (Mulberry32).
const генератор = vm.runInNewContext('(' + ТЕКСТ_ГЕНЕРАТОРА.replace('function генератор', 'function') + ')');

// Решение бота в песочнице с пределом времени. Отдаёт { черновик, мс } или { ошибка }.
function решитьСПределом(песочница, партияJSON, место, уровень, зерно) {
  песочница.ПАРТИЯ = партияJSON;
  const вызов = 'JSON.stringify(window.ЗахватБот.решить(JSON.parse(ПАРТИЯ), ' +
    JSON.stringify(место) + ', ' + JSON.stringify(уровень) + ', генератор(' + зерно + ')))';
  const начало = process.hrtime.bigint();
  try {
    const текст = vm.runInContext(вызов, песочница, { timeout: ПРЕДЕЛ_ВЫЗОВА_МС });
    const мс = Number(process.hrtime.bigint() - начало) / 1e6;
    return { черновик: JSON.parse(текст), мс: мс };
  } catch (ошибка) {
    return { ошибка: ошибка.message };
  }
}

