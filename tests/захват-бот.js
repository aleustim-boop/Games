// Источник случая из очереди чисел; считает, сколько чисел вытянуто.
function очередь(числа) {
  let и = 0;
  const случай = function () {
    if (и >= числа.length) throw new Error('бот вытянул больше чисел, чем было в очереди (' + числа.length + ')');
    return числа[и++];
  };
  случай.вытянуто = () => и;
  return случай;
}

function постоянный(число) {
  let вытянуто = 0;
  const случай = function () { вытянуто++; return число; };
  случай.вытянуто = () => вытянуто;
  return случай;
}

