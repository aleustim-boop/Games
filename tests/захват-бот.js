// Источник случая из очереди чисел; считает, сколько чисел вытянуто.
function очередь(числа) {
  let и = 0;
  const случай = function () {
    if (и >= числа.length) throw new Error('бот вытянул больше чисел, чем было в очереди (' + числа.length + ')');
    return числа[и++];
  };
  случай.вытянуто = () => и;
  return случай;
}

function постоянный(число) {
  let вытянуто = 0;
  const случай = function () { вытянуто++; return число; };
  случай.вытянуто = () => вытянуто;
  return случай;
}

// Тестовая карта «пара»: две области A–B, краёв нет. У A единственный сосед — B (случаи 27–29).
// Карта кладётся только в память этого запуска, файл карт не меняется.
function картаПара() {
  if (!Карты.ТЕСТОВЫЕ['бот-пара']) {
    Карты.ТЕСТОВЫЕ['бот-пара'] = {
      ключ: 'бот-пара', название: 'Пара', столбцов: 2, рядов: 1, сетка: ['A B'],
      области: [
        { номер: 1, буква: 'A', имя: 'Один', край: null },
        { номер: 2, буква: 'B', имя: 'Два', край: null }
      ],
      края: [], гнёзда: {}
    };
  }
  return Карты.ТЕСТОВЫЕ['бот-пара'];
}

// Партия руками: карта, хозяева и войска по номерам областей, подкрепления. Столиц нет, если не заданы.
function партияРуками(карта, игроки, хозяева, войска, подкрепление, столицы) {
  const черновики = {};
  игроки.forEach((к) => { черновики[к] = П.пустойЧерновик(); });
  return {
    карта: карта, игроки: игроки, люди: [], началась: null, раунд: 2, всегоРаундов: 12,
    хозяева: [null].concat(хозяева), войска: [0].concat(войска),
    столицы: столицы || [], подкрепление: подкрепление, черновики: черновики, завершена: false
  };
}

