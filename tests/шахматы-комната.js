const СТРОКА_В_РЕЕСТРЕ =
  "  шахматы: проверитьДоговор(require('./шахматы.js'), 'server/игры/шахматы.js'),\n";

/** Скопировать server/ и js/ во временную папку (без данных игроков). */
function сделатьКопию(папка) {
  for (const часть of ['server', 'js']) {
    fs.cpSync(path.join(ПРОЕКТ, часть), path.join(папка, часть), {
      recursive: true,
      filter: function (откуда) {
        const имя = path.basename(откуда);
        return имя !== 'данные' && имя !== 'node_modules';
      }
    });
  }
}

function сломать() {
  console.log('=== Ломающий прогон шахматной комнаты: реестр без шахмат обязан покраснеть ===');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'шахматы-комната-лом-'));
  console.log('копия в ' + папка + '\n');

  сделатьКопию(папка);
  const файлРеестра = path.join(папка, 'server', 'игры', 'реестр.js');
  const текст = fs.readFileSync(файлРеестра, 'utf8');
  if (текст.indexOf(СТРОКА_В_РЕЕСТРЕ) === -1) {
    console.log('ПРОВАЛ: строка шахмат в копии реестра не нашлась — портить нечего');
    process.exit(1);
  }
  fs.writeFileSync(файлРеестра, текст.replace(СТРОКА_В_РЕЕСТРЕ, ''), 'utf8');

  const прогон = spawnSync(process.execPath, [__filename, '--корень', папка], {
    encoding: 'utf8', timeout: 60000
  });
  const вывод = (прогон.stdout || '') + (прогон.stderr || '');
  const покраснелаА = /ПРОВАЛ \[А\]/.test(вывод);
  console.log(вывод);
  console.log('----------------------------------------');
  if (покраснелаА && прогон.status === 1) {
    console.log('красная, как надо: буква А покраснела, код выхода ' + прогон.status);
    process.exit(0);
  }
  console.log('ПРОВАЛ: без строки в реестре ожидали красную букву А, а получили код выхода ' +
    прогон.status + ', покраснела ли А: ' + покраснелаА);
  process.exit(1);
}

