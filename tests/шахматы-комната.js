function подписать(поля, токен) {
  const строки = Object.keys(поля)
    .filter(function (к) { return к !== 'hash'; })
    .map(function (к) { return к + '=' + поля[к]; })
    .sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(токен).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}

/** initData так, как её присылает настоящая страница Telegram. */
function подписьИгрока(номер, имя) {
  const поля = {
    query_id: 'AAF' + номер,
    user: JSON.stringify({ id: номер, first_name: имя, username: 'igrok' + номер }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  const сподписью = Object.assign({}, поля, { hash: подписать(поля, ТОКЕН_ДЛЯ_ПРОБЫ) });
  return Object.keys(сподписью)
    .map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(сподписью[к]); })
    .join('&');
}

function спросить(путь, тело) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН_АДРЕС, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (сбой) { разобрано = null; }
        готово({ код: ответ.statusCode, тело: разобрано || {} });
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

/** Поддельный игрок с настоящим номером Telegram — нужен рейтингу. */
function создатьИгрока(имя, номер) {
  return {
    имя: имя,
    номер: номер,
    код: null,
    пропуск: null,
    вид: null,

    async создать(доп) {
      const ответ = await спросить('/создать', Object.assign(
        { имя: имя, initData: подписьИгрока(номер, имя) }, доп || {}));
      if (ответ.тело && ответ.тело.пропуск) {
        this.код = ответ.тело.код;
        this.пропуск = ответ.тело.пропуск;
        this.вид = ответ.тело.состояние || null;
      }
      return ответ;
    },

    async войти(код) {
      const ответ = await спросить('/войти',
        { код: код, имя: имя, initData: подписьИгрока(номер, имя) });
      if (ответ.тело && ответ.тело.пропуск) {
        this.код = ответ.тело.код;
        this.пропуск = ответ.тело.пропуск;
        this.вид = ответ.тело.состояние || null;
      }
      return ответ;
    },

    async состояние() {
      const ответ = await спросить('/состояние', { код: this.код, пропуск: this.пропуск });
      if (ответ.тело && ответ.тело.состояние) this.вид = ответ.тело.состояние;
      return ответ;
    },

    async ход(действие, доп) {
      const ответ = await спросить('/ход',
        Object.assign({ код: this.код, пропуск: this.пропуск, действие: действие }, доп || {}));
      if (ответ.тело && ответ.тело.состояние) this.вид = ответ.тело.состояние;
      return ответ;
    },

    async выйти() {
      return спросить('/выйти', { код: this.код, пропуск: this.пропуск });
    }
  };
}

/** Свести двоих людей за стол шахмат; вернуть, кто белый, кто чёрный. */
async function свестиЗаШахматы(первыйНомер, второйНомер) {
  const первый = создатьИгрока('Игрок' + первыйНомер, первыйНомер);
  const второй = создатьИгрока('Игрок' + второйНомер, второйНомер);

  const ответСоздания = await первый.создать({ игра: 'шахматы' });
  проверить('А', ответСоздания.код === 200 && Boolean(первый.пропуск),
    'стол «шахматы» создаётся (ответ /создать: код ' + ответСоздания.код +
    ', ошибка: ' + JSON.stringify(ответСоздания.тело && ответСоздания.тело.ошибка) + ')');
  if (!первый.пропуск) return null;   // без реестра дальше сценарию не на чем стоять

  await второй.войти(первый.код);
  await первый.состояние();

  проверить('А', Boolean(первый.вид) && первый.вид.этап === 'игра',
    'партия стартовала сама, без кнопки «Начать» (этап: ' + (первый.вид && первый.вид.этап) + ')');
  проверить('А', typeof первый.вид.fen === 'string' && первый.вид.fen.length > 10,
    'вид несёт непустой FEN (иначе рокировку и взятие на проходе клиент не соберёт)');
  проверить('А', Boolean(второй.вид) && второй.вид.мойЦвет &&
    первый.вид.мойЦвет && первый.вид.мойЦвет !== второй.вид.мойЦвет,
    'цвета розданы разным местам (первый: ' + (первый.вид && первый.вид.мойЦвет) +
    ', второй: ' + (второй.вид && второй.вид.мойЦвет) + ')');

  if (!первый.вид || !второй.вид) return null;
  const белый = первый.вид.мойЦвет === 'белые' ? первый : второй;
  const чёрный = белый === первый ? второй : первый;
  return { белый: белый, чёрный: чёрный };
}

