/* ---------- свой статический сервер ---------- */

const ТИПЫ = {
  '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'application/javascript; charset=utf-8',
  '.json': 'application/json', '.svg': 'image/svg+xml', '.webp': 'image/webp', '.png': 'image/png', '.jpg': 'image/jpeg',
  '.woff2': 'font/woff2', '.woff': 'font/woff', '.ttf': 'font/ttf'
};

const внутри = (папка, путь) => !path.relative(папка, путь).startsWith('..') && !path.isAbsolute(path.relative(папка, путь));

/** Сервер на свободном порту (не 8790): страница отдаётся без сервера комнат. */
function поднятьСервер() {
  const сервер = http.createServer((запрос, ответ) => {
    let путь = '/';
    try { путь = decodeURIComponent(запрос.url.split('?')[0]); } catch (_) { /* как есть */ }
    const файл = path.join(КОРЕНЬ, путь === '/' ? 'index.html' : путь);
    if (внутри(КОРЕНЬ, файл) && fs.existsSync(файл) && fs.statSync(файл).isFile()) {
      ответ.writeHead(200, { 'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'application/octet-stream' });
      ответ.end(fs.readFileSync(файл));
      return;
    }
    ответ.writeHead(404); ответ.end('нет такого файла');
  });
  return new Promise(готово => сервер.listen(0, '127.0.0.1', () => готово(сервер)));
}

/* ---------- замер экрана в странице ---------- */

/** Выполняется в браузере: всё, что проверяется на одном виде экрана. */
function замеритьЭкран(группы) {
  const ш = window.innerWidth;
  const вОкне = у => { const р = у.getBoundingClientRect(); return р.width > 0 && р.left >= -0.5 && р.right <= ш + 0.5; };
  const состав = document.getElementById('захват-онлайн-состав').getBoundingClientRect();
  const места = Array.from(document.querySelectorAll('#захват-онлайн-стол .рассадка__место'));
  const имена = места.map(м => м.querySelector('.рассадка__имя')).filter(Boolean);
  // Круг места и его подпись не должны заходить на круг или подпись другого места.
  const пятна = места.map(м => [м.getBoundingClientRect()].concat(Array.from(м.querySelectorAll('.рассадка__имя')).map(и => и.getBoundingClientRect())));
  const пересеклись = (а, б) => а.left < б.right - 0.5 && б.left < а.right - 0.5 && а.top < б.bottom - 0.5 && б.top < а.bottom - 0.5;
  const наложения = [];
  for (let и = 0; и < пятна.length; и++) {
    for (let к = и + 1; к < пятна.length; к++) {
      if (пятна[и].some(а => пятна[к].some(б => пересеклись(а, б)))) наложения.push((и + 1) + '×' + (к + 1));
    }
  }
  return {
    виденЭкран: document.getElementById('экран-друга').classList.contains('экран--виден'),
    прокрутка: document.documentElement.scrollWidth > ш + 1,
    кнопок: группы.map(id => document.querySelectorAll('#' + id + ' button').length),
    кнопкиВОкне: группы.every(id => Array.from(document.querySelectorAll('#' + id + ' button')).every(вОкне)),
    мест: места.length,
    местаВОкне: места.every(вОкне),
    имён: имена.length,
    именаВОкне: имена.length > 0 && имена.every(вОкне),
    // Слово не вылезает из пилюли (на 320 «Сложные» заполняло её целиком).
    тесныеПилюли: группы.flatMap(id => Array.from(document.querySelectorAll('#' + id + ' button')))
      .filter(к => к.scrollWidth > к.clientWidth + 0.5).map(к => к.textContent),
    панель: (() => { const п = document.querySelector('#экран-друга .захват-панель'); if (!п) return null; const р = п.getBoundingClientRect(); return { лево: р.left, право: р.right }; })(),
    именаНадСоставом: имена.length > 0 && имена.every(и => и.getBoundingClientRect().bottom <= состав.top + 1),
    наложения: места.length >= 2 ? наложения : ['мест меньше двух']
  };
}

/** Выполняется в браузере: прокрутить всё, что прокручивается вокруг кнопки «Создать игру»,
    до низа (доНиза = true) или до верха. Экран друга прокручивается внутри, не страницей. */
function прокрутить(доНиза) {
  const кнопка = document.getElementById('кнопка-создать-игру');
  for (let у = кнопка && кнопка.parentElement; у; у = у.parentElement) {
    if (у.scrollHeight > у.clientHeight + 1) у.scrollTop = доНиза ? у.scrollHeight : 0;
  }
  window.scrollTo(0, доНиза ? document.documentElement.scrollHeight : 0);
}

/** Выполняется в браузере: «Создать игру» целиком в окне и ничем не закрыта. */
function замеритьКнопку() {
  const кнопка = document.getElementById('кнопка-создать-игру');
  if (!кнопка) return { есть: false };
  const р = кнопка.getBoundingClientRect();
  const ш = window.innerWidth, в = window.innerHeight;
  const целиком = р.width > 0 && р.height > 0 && р.left >= -0.5 && р.right <= ш + 0.5 && р.top >= -0.5 && р.bottom <= в + 0.5;
  // Углы и центр: сверху должна лежать сама кнопка. Угловая точка отступает внутрь
  // на долю радиуса скругления (0,3·r лежит уже внутри дуги), иначе попадает в панель за кнопкой.
  const радиус = Math.min(parseFloat(getComputedStyle(кнопка).borderTopLeftRadius) || 0, р.width / 2, р.height / 2);
  const д = Math.ceil(радиус * 0.3) + 2;
  const точки = [[р.left + д, р.top + д], [р.right - д, р.top + д], [р.left + д, р.bottom - д], [р.right - д, р.bottom - д], [(р.left + р.right) / 2, (р.top + р.bottom) / 2]];
  const закрыто = точки.map(([x, y]) => {
    const сверху = document.elementFromPoint(x, y);
    if (сверху && (сверху === кнопка || кнопка.contains(сверху))) return null;
    return Math.round(x) + ',' + Math.round(y) + ' → ' + (сверху ? сверху.tagName.toLowerCase() + (сверху.id ? '#' + сверху.id : '') + (сверху.className ? '.' + String(сверху.className).split(' ').join('.') : '') : 'пусто');
  }).filter(Boolean);
  const видна = у => { const с = getComputedStyle(у); const п = у.getBoundingClientRect(); return с.display !== 'none' && с.visibility !== 'hidden' && п.width > 0 && п.height > 0; };
  const полосыНаКнопке = Array.from(document.querySelectorAll('.нижние-вкладки')).filter(видна)
    .filter(п => { const пр = п.getBoundingClientRect(); return пр.top < р.bottom - 0.5 && пр.bottom > р.top + 0.5; }).length;
  // Ряд «Уже пригласили? · Ввести код» под панелью: кнопка не наезжает на текст.
  const код = document.getElementById('кнопка-войти-по-коду');
  const текстКода = код && код.parentElement ? код.parentElement.querySelector(':scope > div') : null;
  let кодНаТексте = 'нет кнопки или текста';
  if (код && текстКода && видна(код)) {
    const а = код.getBoundingClientRect(), б = текстКода.getBoundingClientRect();
    // Сжатый в ноль текст — та же поломка: кнопка забрала его место.
    кодНаТексте = б.width < 60 ? 'текст «Уже пригласили?» сжат до ' + Math.round(б.width) + ' точек'
      : а.right > ш + 0.5 ? 'кнопка выходит за край экрана: ' + Math.round(а.right)
      : а.left < б.right - 0.5 && б.left < а.right - 0.5 && а.top < б.bottom - 0.5 && б.top < а.bottom - 0.5
      ? 'кнопка ' + Math.round(а.left) + '..' + Math.round(а.right) + ', текст ' + Math.round(б.left) + '..' + Math.round(б.right) : '';
  }
  return { есть: true, целиком, закрыто, полосыНаКнопке, низ: Math.round(р.bottom), высотаОкна: в, кодНаТексте };
}

/* ---------- обход ---------- */

async function снять() {
  const { chromium, подготовитьПодделку } = require(path.join(КОРЕНЬ, 'tests', 'браузер-робот.js'));
  const ПАПКА = path.join(КОРЕНЬ, 'tests', 'снимки', 'захват');
  fs.mkdirSync(ПАПКА, { recursive: true });
  const сервер = await поднятьСервер();
  const порт = сервер.address().port;
  const браузер = await chromium.launch();
  const снимки = [];
  try {
    for (const [ш, в] of [[320, 568], [390, 844]]) {
      const контекст = await браузер.newContext({ viewport: { width: ш, height: в } });
      const страница = await контекст.newPage();
      await подготовитьПодделку(страница, {});
      const ошибки = [];
      страница.on('console', с => { if (с.type() === 'error' && (с.location().url || '').indexOf('telegram-web-app.js') === -1) ошибки.push(с.text()); });
      страница.on('pageerror', е => ошибки.push('необработанная ошибка: ' + е.message));
      страница.on('response', о => { if (о.status() === 404) ошибки.push('404: ' + о.url()); });
      await страница.goto('http://127.0.0.1:' + порт + '/захват.html', { waitUntil: 'load' });
      await страница.waitForTimeout(600);
      if (НИЗКИЙ_СТОЛ) {
        // Порча только в странице браузера: низкий овал и при 6 местах.
        await страница.addStyleTag({ content: '.захват-панель .захват-онлайн-рассадка { aspect-ratio: 2.15 / 1 !important; }' });
      }
      if (УЗКИЕ_ПОЛЯ) {
        // Порча только в странице браузера: экран друга снова с общими полями 10 точек.
        await страница.addStyleTag({ content: 'body.захват #экран-друга { padding-left: 10px !important; padding-right: 10px !important; }' });
      }
      if (ТЕСНЫЕ_ПИЛЮЛИ) {
        // Порча только в странице браузера: широкие поля внутри пилюль — слово не помещается.
        await страница.addStyleTag({ content: '.захват-выбор-числа > button { padding-inline: 40px !important; }' });
      }
      if (ШИРОКИЙ_КОД) {
        // Порча только в странице браузера: «Ввести код» снова шириной колонки кнопок.
        await страница.addStyleTag({ content: 'body.захват .деберц-пригласили .кнопка { width: 300px !important; }' });
      }
      // Колонка лобби — образец боковых полей для экрана друга (те же края карточек входов).
      const колонкаЛобби = await страница.evaluate(() => {
        const к = Array.from(document.querySelectorAll('#экран-лобби .карточка-входа')).find(у => у.getBoundingClientRect().width > 0);
        if (!к) return null;
        const р = к.getBoundingClientRect();
        return { лево: р.left, право: р.right };
      });
      проверка('снимки ' + ш + ': колонка лобби найдена (карточка входа)', !!колонкаЛобби);
      await страница.evaluate(() => window.ЗахватЭкран.показатьЭкран('экран-друга'));
      await страница.waitForTimeout(400);
      if (ПОЛОСА_ПОВЕРХ) {
        // Порча только в странице браузера: поверх низа экрана лежит полоса вкладок. Высокая (60% окна):
        // под «Создать игру» есть ещё «Уже пригласили?» и «Назад», и низкая полоса кнопку не задела бы.
        await страница.evaluate(() => {
          const полоса = document.createElement('nav');
          полоса.className = 'нижние-вкладки';
          полоса.setAttribute('style', 'position:fixed;left:0;right:0;bottom:0;height:60vh;z-index:9999;display:block;background:#222;');
          document.body.appendChild(полоса);
        });
      }
      for (const шестьМест of [false, true]) {
        if (шестьМест) {
          await страница.click('#захват-онлайн-число button[data-значение="6"]');
          await страница.waitForTimeout(200);
        }
        await страница.evaluate(прокрутить, false);
        await страница.waitForTimeout(100);
        const замер = await страница.evaluate(замеритьЭкран, ГРУППЫ.map(г => г.id));
        const подпись = 'снимки ' + ш + (шестьМест ? ', 6 мест' : '') + ': ';
        const ждёмКнопок = ГРУППЫ.map(г => г.кнопок).join('/');
        проверка(подпись + '#экран-друга виден', замер.виденЭкран);
        проверка(подпись + 'нет горизонтальной прокрутки', !замер.прокрутка);
        проверка(подпись + 'кнопок в группах ' + ждёмКнопок, замер.кнопок.join('/') === ждёмКнопок, замер.кнопок.join('/'));
        проверка(подпись + 'пилюли целиком в окне', замер.кнопкиВОкне);
        проверка(подпись + 'места стола есть и в окне', замер.мест === (шестьМест ? 6 : 4) && замер.местаВОкне, 'мест ' + замер.мест);
        проверка(подпись + 'у каждого места подпись', замер.имён === замер.мест, 'подписей ' + замер.имён);
        проверка(подпись + 'подписи мест целиком в окне', замер.именаВОкне);
        проверка(подпись + 'слова не вылезают из пилюль', замер.тесныеПилюли.length === 0, 'тесно: ' + замер.тесныеПилюли.join(', '));
        проверка(подпись + 'панель по краям колонки лобби',
          !!колонкаЛобби && !!замер.панель && Math.abs(замер.панель.лево - колонкаЛобби.лево) <= 1 && Math.abs(замер.панель.право - колонкаЛобби.право) <= 1,
          'панель ' + (замер.панель ? Math.round(замер.панель.лево) + '..' + Math.round(замер.панель.право) : 'нет') + ', лобби ' + (колонкаЛобби ? Math.round(колонкаЛобби.лево) + '..' + Math.round(колонкаЛобби.право) : 'нет'));
        проверка(подпись + 'подписи мест не налезают на состав', замер.именаНадСоставом);
        проверка(подпись + 'места и подписи не налезают друг на друга', замер.наложения.length === 0, 'наложились: ' + замер.наложения.join(', '));
        if (!ЛОМАЕМ) {
          const файл = path.join(ПАПКА, 'захват-друг' + (шестьМест ? '-6мест' : '') + '-' + ш + '.png');
          await страница.screenshot({ path: файл, fullPage: true });
          снимки.push(файл);
        }
        // Низ экрана: «Время на раунд», «Раундов», карта и «Создать игру» видны только после прокрутки.
        await страница.evaluate(прокрутить, true);
        await страница.waitForTimeout(150);
        const низ = await страница.evaluate(замеритьКнопку);
        проверка(подпись + 'кнопка «Создать игру» есть', низ.есть);
        проверка(подпись + '«Создать игру» после прокрутки целиком в окне', низ.есть && низ.целиком, 'низ кнопки ' + низ.низ + ' при высоте окна ' + низ.высотаОкна);
        проверка(подпись + '«Создать игру» ничем не закрыта', низ.есть && низ.закрыто.length === 0, (низ.закрыто || []).join('; '));
        проверка(подпись + 'нижняя полоса не заходит на «Создать игру»', низ.есть && низ.полосыНаКнопке === 0, 'полос на кнопке: ' + низ.полосыНаКнопке);
        проверка(подпись + '«Ввести код» не наезжает на «Уже пригласили?»', низ.есть && низ.кодНаТексте === '', низ.кодНаТексте);
        if (!ЛОМАЕМ && !шестьМест) {
          const файл = path.join(ПАПКА, 'захват-друг-низ-' + ш + '.png');
          await страница.screenshot({ path: файл });
          снимки.push(файл);
        }
      }
      проверка('снимки ' + ш + ': консоль чистая, 404 нет', ошибки.length === 0, ошибки.join(' | '));
      await контекст.close();
    }
  } finally {
    await браузер.close();
    сервер.close();
  }
  снимки.forEach(ф => console.log('Снимок: ' + path.relative(КОРЕНЬ, ф)));
}

async function главная() {
  try { await снять(); } catch (ошибка) {
    всего++; провалов++;
    console.log('ПРОВАЛ: обход упал — ' + (ошибка && ошибка.stack ? ошибка.stack.split('\n').slice(0, 3).join(' / ') : ошибка));
  }
  console.log('Итого проверок: ' + всего + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
}

главная();
