function проверить(условие, слова) {
  проверок++;
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
  return условие;
}
function сказать(слова) { console.log('  ' + слова); }

/* -------------------------------------------------------------------
   Свой файловый сервер: отдаёт заданный корень как есть. Тот же приём,
   что в tests/браузер-казуальные-кнопка-рейтинг.js и tests/локальный-сервер.js.
   ------------------------------------------------------------------- */
const ТИПЫ = {
  '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8', '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg', '.webp': 'image/webp', '.woff2': 'font/woff2', '.mp3': 'audio/mpeg'
};
function запрещённыйАдрес(адрес) {
  const низ = адрес.toLowerCase();
  if (низ.indexOf('.env') !== -1) return true;
  const части = низ.split(/[\\/]/).filter(Boolean);
  if (части.length && части[0] === 'bot') return true;
  return части.some(function (ч) { return ч.charAt(0) === '.'; });
}
/* Возвращает {сервер, порт} — порт может отличаться от запрошенного: если
   тот занят чужим процессом (боевой 8080 с 23.09, гасить нельзя), при
   EADDRINUSE слушаем на 0 (свободный порт от системы) вместо падения. */
function поднятьФайловыйСервер(корень, порт) {
  return new Promise(function (готово, отказ) {
    const сервер = http.createServer(function (запрос, ответ) {
      let адрес;
      try { адрес = decodeURIComponent(запрос.url.split('?')[0]); }
      catch (о) { ответ.writeHead(400); ответ.end('непонятный адрес'); return; }
      if (адрес === '/') адрес = '/index.html';
      if (запрещённыйАдрес(адрес)) { ответ.writeHead(403); ответ.end('доступ закрыт'); return; }
      const файл = path.join(корень, адрес.replace(/^\/+/, ''));
      if (файл !== корень && !файл.startsWith(корень + path.sep)) {
        ответ.writeHead(403); ответ.end('доступ закрыт: файл вне папки'); return;
      }
      fs.readFile(файл, function (ошибка, данные) {
        if (ошибка) { ответ.writeHead(404); ответ.end('не найдено: ' + адрес); return; }
        ответ.writeHead(200, {
          'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'application/octet-stream',
          'Cache-Control': 'no-store'
        });
        ответ.end(данные);
      });
    });
    let ужеПробовалиЗапасной = false;
    сервер.on('error', function (ошибка) {
      if (ошибка && ошибка.code === 'EADDRINUSE' && !ужеПробовалиЗапасной) {
        ужеПробовалиЗапасной = true;
        сервер.listen(0, '127.0.0.1');
        return;
      }
      отказ(ошибка);
    });
    сервер.on('listening', function () {
      const реальныйПорт = сервер.address().port;
      if (реальныйПорт !== порт) console.log('порт ' + порт + ' занят, страницы на ' + реальныйПорт);
      готово({ сервер: сервер, порт: реальныйПорт });
    });
    сервер.listen(порт, '127.0.0.1');
  });
}
function постучать(адрес) {
  return new Promise(function (готово) {
    const з = http.get(адрес, function (о) { о.resume(); готово(о.statusCode); });
    з.on('error', function () { готово(0); });
    з.setTimeout(1500, function () { з.destroy(); готово(0); });
  });
}
async function дождатьсяСервера(адресКорня) {
  for (let п = 0; п < 40; п++) {
    if (await постучать(адресКорня + '/index.html')) return true;
    await new Promise(function (г) { setTimeout(г, 150); });
  }
  return false;
}

async function дождатьсяЭкрана(страница, id, мс) {
  try {
    await страница.waitForFunction(function (и) {
      const э = document.getElementById(и);
      return Boolean(э && э.classList.contains('экран--виден'));
    }, id, { timeout: мс || 8000 });
    return true;
  } catch (сбой) { return false; }
}

/* -------------------------------------------------------------------
   Один сценарий: открыть страницу без Telegram, собрать консоль,
   сетевые запросы к /друзья-онлайн, проверить пять пунктов из шапки.
   ------------------------------------------------------------------- */
async function проверитьСтраницу(браузер, адресКорня, файл) {
  console.log('\n### ' + файл + ' ###');
  const контекст = await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
  const страница = await контекст.newPage();
  await безTelegram(страница); // только обрывает настоящий telegram-web-app.js — Telegram не подделываем вовсе

  const красные = [];
  const логи = [];
  const запросыДрузьяОнлайн = [];
  страница.on('pageerror', function (о) { красные.push('падение: ' + о.message); });
  страница.on('console', function (м) {
    логи.push(м.text());
    if (м.type() !== 'error') return;
    const текст = м.text();
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js|telegram\.org/.test(текст + ' ' + откуда)) return;
    красные.push('консоль: ' + текст + (откуда ? ' (' + откуда + ')' : ''));
  });
  страница.on('request', function (запрос) {
    const адрес = decodeURIComponent(запрос.url());
    if (/\/друзья-онлайн(?:\?|$)/.test(адрес)) запросыДрузьяОнлайн.push(адрес);
  });

  let открылась = true;
  try {
    await страница.goto(адресКорня + '/' + файл, { waitUntil: 'domcontentloaded', timeout: 15000 });
  } catch (о) {
    открылась = false;
    красные.push('страница не открылась: ' + (о && о.message));
  }
  проверить(открылась, файл + ': страница открылась');

  // Три секунды тишины — время как раз для проверки «не постучали на /друзья-онлайн».
  await страница.waitForTimeout(3000);

  const естьСеть = await страница.evaluate(function () { return typeof window.Сеть !== 'undefined' && window.Сеть !== null; }).catch(function () { return false; });
  проверить(естьСеть, файл + ': window.Сеть существует');

  const естьСтрокаВыключено = логи.some(function (т) { return т.indexOf(СТРОКА_СЕТЬ_ВЫКЛЮЧЕНА) !== -1; });
  проверить(естьСтрокаВыключено, файл + ': в консоли есть строка «' + СТРОКА_СЕТЬ_ВЫКЛЮЧЕНА + '»');

  проверить(запросыДрузьяОнлайн.length === 0,
    файл + ': за 3 секунды ни одного запроса на /друзья-онлайн' +
    (запросыДрузьяОнлайн.length ? ' (ушло: ' + запросыДрузьяОнлайн.join(', ') + ')' : ''));

  const экранВиден = await дождатьсяЭкрана(страница, 'экран-лобби', 4000);
  проверить(экранВиден, файл + ': главный экран #экран-лобби виден (класс «экран--виден»)');

  проверить(красные.length === 0, файл + ': консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));

  const итогСтраницы = открылась && естьСеть && естьСтрокаВыключено &&
    запросыДрузьяОнлайн.length === 0 && экранВиден && красные.length === 0;
  console.log((итогСтраницы ? 'OK' : 'ПРОВАЛ') + ' — ' + файл);

  await контекст.close();
  return итогСтраницы;
}

/* -------------------------------------------------------------------
   Приём порчи (--сломать): копия всего проекта во временную папку,
   в копии общее/js/сеть.js первой строкой — throw new Error('порча').
   Тот же приём копирования, что в tests/деберц-два-браузера.js.
   ------------------------------------------------------------------- */
function сделатьПорченуюКопию() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'головоломки-сеть-лом-'));
  for (const часть of [...require('./пути-проекта.js').папкиКода(), 'img']) {
    const откуда = path.join(ПРОЕКТ, часть);
    if (!fs.existsSync(откуда)) continue;
    fs.cpSync(откуда, path.join(папка, часть), {
      recursive: true,
      filter: function (ф) { const имя = path.basename(ф); return имя !== 'данные' && имя !== 'node_modules'; }
    });
  }
  for (const файл of fs.readdirSync(ПРОЕКТ)) {
    if (файл.endsWith('.html') || файл.endsWith('.css')) fs.copyFileSync(path.join(ПРОЕКТ, файл), path.join(папка, файл));
  }
  const путьСети = path.join(папка, 'общее', 'js', 'сеть.js');
  const исходныйТекст = fs.readFileSync(путьСети, 'utf8');
  fs.writeFileSync(путьСети, "throw new Error('порча');\n" + исходныйТекст, 'utf8');
  return папка;
}

