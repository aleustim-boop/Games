(async function () {
  console.log('=== Восемь головоломок после подключения общее/js/сеть.js (браузер) ===');
  if (СЛОМАТЬ) console.log('РЕЖИМ: --сломать (копия проекта во временной папке, порчен общее/js/сеть.js)');

  const браузер = await chromium.launch();

  if (!СЛОМАТЬ) {
    const итог = await поднятьФайловыйСервер(ПРОЕКТ, ПОРТ);
    const сервер = итог.сервер;
    const адресКорня = 'http://127.0.0.1:' + итог.порт;
    console.log('свой сервер: ' + адресКорня + ' (корень проекта, боевой 8790 не трогаем)');
    const готовСервер = await дождатьсяСервера(адресКорня);
    проверить(готовСервер, 'свой файловый сервер поднялся (' + итог.порт + ')');
    if (готовСервер) {
      for (const файл of СТРАНИЦЫ) {
        await проверитьСтраницу(браузер, адресКорня, файл);
      }
    } else {
      сказать('Дальше проверять нечего.');
    }
    await браузер.close();
    await new Promise(function (г) { сервер.close(г); });
  } else {
    const папка = сделатьПорченуюКопию();
    сказать('порченая копия: ' + папка);
    const итог = await поднятьФайловыйСервер(папка, ПОРТ_ЛОМ);
    const сервер = итог.сервер;
    const адресКорня = 'http://127.0.0.1:' + итог.порт;
    console.log('свой сервер (лом): ' + адресКорня);
    const готовСервер = await дождатьсяСервера(адресКорня);
    проверить(готовСервер, 'свой файловый сервер (лом) поднялся (' + итог.порт + ')');
    if (готовСервер) {
      await проверитьСтраницу(браузер, адресКорня, 'mahjong.html');
    } else {
      сказать('Дальше проверять нечего.');
    }
    await браузер.close();
    await new Promise(function (г) { сервер.close(г); });
    fs.rmSync(папка, { recursive: true, force: true });
    сказать('временная копия убрана: ' + папка);
  }

  console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);

  if (СЛОМАТЬ) {
    if (провалов === 0) {
      console.log('ПЛОХО: ломающий запуск не покраснел — проверка ничего не стережёт.');
      process.exit(1);
    }
    console.log('Ломающий запуск покраснел, как и должен.');
    process.exit(0);
  }
  process.exit(провалов ? 1 : 0);
})().catch(function (о) {
  console.error('Проверка упала: ' + (о && о.stack || о));
  process.exit(2);
});
