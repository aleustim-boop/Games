/**
 * вТелеграме=true (по умолчанию) — обычная подделка Telegram.WebApp
 * с initData, как раньше: так снимаются лобби, партия и т.д.
 *
 * вТелеграме=false — страница БЕЗ подделки Telegram, только настоящий
 * telegram-web-app.js не пускаем (безTelegram из tests/браузер-робот.js).
 * Нужно ровно двум состояниям — «как-играть» и «лист-ещё»: их сценарий
 * кликает по браузерной кнопке «⋯» (#кнопка-лобби-ещё), а она нарочно
 * скрыта, когда страница думает, что открыта ВНУТРИ Telegram (style.css:
 * «html.в-телеграме .верх-игры{display:none}» — её место занимают
 * системная стрелка «Назад» и системный пункт «Настройки»). Подделка с
 * initData как раз и заставляет js/telegram.js поставить класс
 * «в-телеграме» (см. открытоВTelegram() в js/telegram.js) — кнопка
 * получает 0×0/offsetParent:null, клик виснет по таймауту, хотя игроку
 * в Telegram всё работает штатно (см. отчёт тестировщика). Без подделки
 * window.Telegram не существует вовсе, класс не ставится, кнопка видна
 * как в обычном браузере — тот же путь, что и у tests/шахматы-первый-
 * взгляд.js для его нетелеграмных проверок. */
async function новаяСтраница(браузер, адрес, файл, вТелеграме) {
  const контекст = await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
  const страница = await контекст.newPage();

  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const т = м.text();
    const откуда = (м.location() && м.location().url) || '';
    if (/telegram-web-app\.js|telegram\.org/.test(т) || /telegram-web-app\.js|telegram\.org/.test(откуда)) return;
    красные.push('консоль: ' + т);
  });
  страница.on('requestfailed', (з) => {
    const адресЗапроса = з.url();
    if (/telegram-web-app\.js|telegram\.org/.test(адресЗапроса)) return;
    красные.push('сеть: ' + адресЗапроса + ' — ' + (з.failure() && з.failure().errorText));
  });

  if (вТелеграме === false) {
    await безTelegram(страница);
  } else {
    await подготовитьПодделку(страница, { версия: '8.0' });
  }
  await страница.goto(адрес + '/' + файл);
  await страница.waitForTimeout(700);

  return { контекст: контекст, страница: страница, красные: красные };
}

/* ---------------------------------------------------------------------
   НАДЁЖНЫЙ СНИМОК: найдена настоящая гонка в самом тесте, не в игре.

   На ширинах 320 и 390 «page.screenshot()» иногда возвращал кадр СРАНЬШЕ,
   чем Chromium успевал перерисовать экран после «setViewportSize» — layout
   (DOM-геометрия, которую меряет «собратьЗамеры») к этому моменту уже
   правильный, а битовая картинка ещё старая/недорисованная. Итог —
   снимок почти чёрный: видна только нижняя полоса вкладок, карточек
   лобби нет, хотя сама страница в порядке (см. отчёт тестировщика от
   23.09: «шашки-лобби-пусто-320.png» и «шахматы-лобби-пусто-320.png»
   и даже «нарды-лобби-пусто-320.png» — байт в байт ОДИН И ТОТ ЖЕ файл
   у трёх разных игр и двух разных состояний, что и выдало гонку: это
   не контент страницы, а один и тот же недорисованный кадр «фон +
   нижняя полоса»). Разово подождать дольше не бронирует от повтора —
   гонка зависит от того, чем занята машина в момент прогона (штаб
   держит несколько исполнителей параллельно), поэтому вместо одной
   фиксированной паузы — самопроверяющийся повтор: снимаем кадр, тут же
   меряем его пиксели (без сторонних библиотек, только встроенный zlib),
   и если кадр подозрительно тёмный — ждём ещё и снимаем заново.
   --------------------------------------------------------------------- */

const ПОРОГ_МАКС_ЯРКОСТИ = 200; // белый текст и салатовые кнопки лобби всегда дают пиксель ≥ ~244; фон и серые иконки полосы — не выше ~138
const ПОПЫТОК_СНИМКА_МАКС = 4;

/** Минимальный декодер PNG (8 бит на канал, без палитры) — ровно то, что отдаёт page.screenshot(). */
function decodePNG(буфер) {
  if (буфер.length < 8 || буфер.readUInt32BE(0) !== 0x89504e47) throw new Error('не похоже на PNG (нет сигнатуры)');
  let смещение = 8;
  let ширина = 0, высота = 0, битГлубина = 0, типЦвета = 0;
  const idatЧасти = [];
  while (смещение + 8 <= буфер.length) {
    const длина = буфер.readUInt32BE(смещение);
    const тип = буфер.toString('ascii', смещение + 4, смещение + 8);
    const данные = буфер.subarray(смещение + 8, смещение + 8 + длина);
    if (тип === 'IHDR') {
      ширина = данные.readUInt32BE(0); высота = данные.readUInt32BE(4);
      битГлубина = данные.readUInt8(8); типЦвета = данные.readUInt8(9);
    } else if (тип === 'IDAT') {
      idatЧасти.push(данные);
    } else if (тип === 'IEND') {
      break;
    }
    смещение += 8 + длина + 4;
  }
  if (битГлубина !== 8) throw new Error('ожидался PNG с 8 битами на канал, получено ' + битГлубина);
  const каналов = { 0: 1, 2: 3, 4: 2, 6: 4 }[типЦвета];
  if (!каналов) throw new Error('неподдержанный тип цвета PNG: ' + типЦвета + ' (палитра не разбирается)');
  const сырые = zlib.inflateSync(Buffer.concat(idatЧасти));
  const байтСтроки = ширина * каналов;
  const пиксели = Buffer.alloc(высота * байтСтроки);
  let вход = 0;
  let предыдущаяСтрока = Buffer.alloc(байтСтроки);
  for (let y = 0; y < высота; y++) {
    const типФильтра = сырые[вход]; вход++;
    const строка = сырые.subarray(вход, вход + байтСтроки);
    вход += байтСтроки;
    const результат = Buffer.alloc(байтСтроки);
    for (let x = 0; x < байтСтроки; x++) {
      const raw = строка[x];
      const a = x >= каналов ? результат[x - каналов] : 0;
      const b = предыдущаяСтрока[x];
      const c = x >= каналов ? предыдущаяСтрока[x - каналов] : 0;
      let значение;
      if (типФильтра === 0) значение = raw;
      else if (типФильтра === 1) значение = raw + a;
      else if (типФильтра === 2) значение = raw + b;
      else if (типФильтра === 3) значение = raw + Math.floor((a + b) / 2);
      else if (типФильтра === 4) {
        const p = a + b - c;
        const pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c);
        значение = raw + (pa <= pb && pa <= pc ? a : (pb <= pc ? b : c));
      } else throw new Error('неизвестный тип фильтра строки PNG: ' + типФильтра);
      результат[x] = значение & 0xff;
    }
    результат.copy(пиксели, y * байтСтроки);
    предыдущаяСтрока = результат;
  }
  return { ширина: ширина, высота: высота, каналов: каналов, пиксели: пиксели };
}

/** Максимальная яркость и доля заметно светлых пикселей — сэмплом по кадру (быстро, без честного полного прохода). */
function яркостьСнимка(буфер) {
  const { ширина, высота, каналов, пиксели } = decodePNG(буфер);
  const шаг = 3;
  let макс = 0, ярких = 0, всего = 0;
  for (let y = 0; y < высота; y += шаг) {
    for (let x = 0; x < ширина; x += шаг) {
      const idx = (y * ширина + x) * каналов;
      const яркость = 0.299 * пиксели[idx] + 0.587 * пиксели[idx + 1] + 0.114 * пиксели[idx + 2];
      if (яркость > макс) макс = яркость;
      if (яркость > 150) ярких++;
      всего++;
    }
  }
  return { максЯркость: макс, долюЯркихПроцентов: всего ? (100 * ярких / всего) : 0 };
}

/** Снимок с самопроверкой: подозрительно тёмный кадр (недорисованный) — ждём ещё и пробуем заново, до ПОПЫТОК_СНИМКА_МАКС раз. */
async function снятьСнимокНадёжно(страница) {
  let буфер = null, метрика = { максЯркость: 0, долюЯркихПроцентов: 0 }, ошибкаРазбора = null;
  for (let попытка = 1; попытка <= ПОПЫТОК_СНИМКА_МАКС; попытка++) {
    // ждём два кадра компоновки — стандартный приём «дать браузеру дорисовать» после resize/DOM-правок.
    await страница.evaluate(() => new Promise((готово) => requestAnimationFrame(() => requestAnimationFrame(готово))));
    буфер = await страница.screenshot();
    try {
      метрика = яркостьСнимка(буфер);
      ошибкаРазбора = null;
    } catch (е) {
      ошибкаРазбора = е; // не смогли разобрать PNG — не мешаем прогону, просто не проверяем яркость этой попытки
      break;
    }
    if (метрика.максЯркость >= ПОРОГ_МАКС_ЯРКОСТИ) return { буфер: буфер, метрика: метрика, попыток: попытка, ошибкаРазбора: null };
    await страница.waitForTimeout(250 * попытка);
  }
  return { буфер: буфер, метрика: метрика, попыток: ПОПЫТОК_СНИМКА_МАКС, ошибкаРазбора: ошибкаРазбора };
}

/** Прогон замеров и снимков по всем четырём ширинам для уже готового состояния. */
async function прогонШиринами(страница, метка, игра, снимки) {
  for (const ширина of ШИРИНЫ) {
    const высота = ширина < 700 ? 844 : 1000;
    await страница.setViewportSize({ width: ширина, height: высота });
    await страница.waitForTimeout(300);
    const состояниеИмя = игра.имя + '/' + метка;
    const замеры = await собратьЗамеры(страница);
    записатьНаходки(состояниеИмя, ширина, 'пересекаются интерактивные элементы', замеры.пересечения);
    записатьНаходки(состояниеИмя, ширина, 'обрезанный текст без многоточия', замеры.обрезанные);
    записатьНаходки(состояниеИмя, ширина, 'зазор меньше 8px между кнопками', замеры.тесныЗазоры);
    записатьНаходки(состояниеИмя, ширина, 'элемент вылезает за край экрана', замеры.заЭкраном);
    записатьНаходки(состояниеИмя, ширина, 'элемент недостижим даже прокруткой предка', замеры.недостижимые);
    проверить(состояниеИмя, ширина, 'нет горизонтальной прокрутки страницы', !замеры.прокруткаЕсть, замеры.прокруткаДеталь);

    const путьСнимка = path.join(ПАПКА_СНИМКОВ, игра.имя + '-' + метка + '-' + ширина + '.png');
    const { буфер, метрика, попыток, ошибкаРазбора } = await снятьСнимокНадёжно(страница);
    fs.writeFileSync(путьСнимка, буфер);
    if (ошибкаРазбора) {
      провалКрахом(состояниеИмя + ' ' + ширина, new Error('снимок сохранён, но не разобрался как PNG: ' + ошибкаРазбора.message));
    } else {
      проверить(состояниеИмя, ширина, 'снимок не почти пустой/недорисованный (максЯркость=' + Math.round(метрика.максЯркость) + ' из 255, порог ' + ПОРОГ_МАКС_ЯРКОСТИ + ')',
        метрика.максЯркость >= ПОРОГ_МАКС_ЯРКОСТИ,
        'попыток снять: ' + попыток + ', доля ярких пикселей ' + метрика.долюЯркихПроцентов.toFixed(2) + '%, файл ' + path.basename(путьСнимка));
    }
    снимки.push({
      игра: игра.имя, метка: метка, ширина: ширина,
      хэш: crypto.createHash('sha1').update(буфер).digest('hex'), путь: путьСнимка
    });
  }
}

