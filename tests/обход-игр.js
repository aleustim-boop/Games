async function кликНеЗависая(страница, состояние, ширина, селектор, описание) {
  try {
    await страница.click(селектор, { timeout: ТАЙМАУТ_ДЕЙСТВИЯ });
    return true;
  } catch (ошибка) {
    проверить(состояние, ширина, 'клик по «' + описание + '» удался (' + селектор + ')', false,
      'не дождался: ' + (ошибка && ошибка.message ? ошибка.message.split('\n')[0] : ошибка));
    return false;
  }
}

