/**
 * режим===null   — старый общий набор: наезд карточек лобби друг на друга,
 *                   горизонтальная прокрутка (min-width:2000px), пропавший
 *                   резерв снизу под нижнюю полосу — всё разом.
 * режим==='наезд' — узкий режим БЕЗ min-width:2000px (та маскирует наезд
 *                   лобби×полоса горизонтальной прокруткой и разъездом всех
 *                   координат — заодно проверяет, что чинёная проверка не
 *                   объявляет ПЛОХО из-за самого сдвига). Только пропавший
 *                   резерв снизу лобби и снятая обрезка у прокручиваемых
 *                   списков (.таблица) — должен дать ПЛОХО «наезд лобби ×
 *                   полоса» и живую (не замаскированную) поломку в списке
 *                   правил, раз обрезка больше не прячет вылезший хвост.
 */
function создатьИспорченныйStyleCss(режим) {
  const оригинал = fs.readFileSync(ПУТЬ_СТИЛЯ, 'utf8');

  if (режим === 'наезд') {
    const маркерБ = '#экран-лобби {';
    if (оригинал.indexOf(маркерБ) === -1) {
      throw new Error('Поломка «наезд/б»: в style.css не нашёлся селектор «' + маркерБ + '».');
    }
    const маркерГ = '.таблица {';
    if (оригинал.indexOf(маркерГ) === -1) {
      throw new Error('Поломка «наезд/г»: в style.css не нашёлся селектор «' + маркерГ + '» — ' +
        'похоже, класс прокручиваемого списка (правила, рекорды) переименовали, поломку нужно поправить вслед за ним.');
    }
    return оригинал +
      '\n/* --- ломающий прогон tests/обход-игр.js --сломать=наезд --- */\n' +
      '#экран-лобби { padding-bottom: 0 !important; }\n' +
      '.таблица { overflow: visible !important; }\n';
  }

  const маркерА = '.лобби__входы {';
  if (оригинал.indexOf(маркерА) === -1) {
    throw new Error('Поломка «а»: в style.css не нашёлся селектор «' + маркерА + '» — ' +
      'похоже, класс контейнера карточек входа переименовали, поломку нужно поправить вслед за ним.');
  }
  const маркерБ = '#экран-лобби {';
  if (оригинал.indexOf(маркерБ) === -1) {
    throw new Error('Поломка «б»: в style.css не нашёлся селектор «' + маркерБ + '».');
  }
  const маркерВ = '#экран-лобби:has(> .нижние-вкладки) {';
  if (оригинал.indexOf(маркерВ) === -1) {
    throw new Error('Поломка «в»: в style.css не нашёлся селектор «' + маркерВ + '» — ' +
      'похоже, резерв снизу под нижнюю полосу переименовали или убрали, поломку нужно поправить вслед за ним.');
  }
  return оригинал +
    '\n/* --- ломающий прогон tests/обход-игр.js --- */\n' +
    '#экран-лобби .лобби__входы .карточка-входа:nth-child(2) {\n  margin-top: -20px !important;\n}\n' +
    '#экран-лобби {\n  min-width: 2000px !important;\n}\n' +
    '#экран-лобби { padding-bottom: 0 !important; }\n';
}

