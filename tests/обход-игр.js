async function сделатьХодыШахматы(страница, число) {
  for (let i = 0; i < число; i++) {
    await страница.evaluate(() => {
      const куда = document.querySelectorAll('.поле--можно');
      if (куда.length) { куда[Math.floor(Math.random() * куда.length)].click(); return; }
      const свои = document.querySelectorAll('.фигура--может-ходить');
      if (свои.length) { свои[Math.floor(Math.random() * свои.length)].click(); return; }
      /* Запасной путь — тот же приём, что в tests/шахматы-первый-взгляд.js
         (раздел «Бот на трёх уровнях»): класса «.фигура--может-ходить»
         в шахматах нет вовсе, поэтому первая ветка выше никогда не
         срабатывает — цикл только смотрит на пустой «.поле--можно» и
         ничего не кликает, партия стоит на месте, а «начало-партии» и
         «середина-партии» выходят байт в байт одинаковыми. Кликаем по
         своей фигуре напрямую («#доска .фигура--белая»), она
         подсвечивает «.поле--можно», и следующая итерация уже сходит
         по первой ветке. */
      const мои = document.querySelectorAll('#доска .фигура--белая');
      if (мои.length) { мои[Math.floor(Math.random() * мои.length)].click(); }
    });
    await страница.waitForTimeout(320);
  }
}

async function сделатьХодыНарды(страница, число) {
  for (let круг = 0; круг < число; круг++) {
    const надоБросить = await страница.evaluate(() => {
      const к = document.getElementById('кнопка-бросить');
      return Boolean(к) && к.offsetParent !== null && !к.disabled;
    });
    if (надоБросить) {
      await страница.click('#кнопка-бросить', { timeout: 4000 }).catch(() => null);
      await страница.waitForTimeout(400);
    }
    for (let попытка = 0; попытка < 6; попытка++) {
      const сходил = await страница.evaluate(() => {
        const можно = document.querySelectorAll('.пункт--можно');
        if (можно.length) { можно[Math.floor(Math.random() * можно.length)].click(); return true; }
        const свои = document.querySelectorAll('.шашка--можно-взять');
        if (свои.length) { свои[Math.floor(Math.random() * свои.length)].click(); return true; }
        return false;
      });
      if (!сходил) break;
      await страница.waitForTimeout(150);
    }
    await страница.evaluate(() => {
      const к = document.getElementById('кнопка-закончить-ход');
      if (к && к.offsetParent !== null && !к.disabled) к.click();
    });
    await страница.waitForTimeout(400);
  }
}

