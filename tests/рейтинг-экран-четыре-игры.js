'use strict';

/* =====================================================================
   Проверка тестировщика: js/рейтинг-экран.js не должен падать ни на одной
   из четырёх игр и ни на одной беде связи.

   Зачем отдельно от браузера. Часть решения («что показать по ответу
   сервера») вынесена в чистую функцию «видПоОтвету» и экспортирована
   именно для того, чтобы её можно было прогнать без браузера — так
   быстрее ловятся забытые случаи («а что если сервер прислал мусор
   про шахматы конкретно»). Запускать: node tests/рейтинг-экран-четыре-игры.js

   Ломающие запусы:
   - node tests/рейтинг-экран-четыре-игры.js --сломать-заголовок
   - node tests/рейтинг-экран-четыре-игры.js --сломать-порядок-пунктов

   Каждый ломающий запуск портит копию файла и требует те же проверки.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const os = require('os');

/* Обработка флагов */
const флагСломатьЗаголовок = process.argv.indexOf('--сломать-заголовок') !== -1;
const флагСломатьПорядок = process.argv.indexOf('--сломать-порядок-пунктов') !== -1;

/* Путь к оригинальному файлу (относительный от папки tests) */
const путьОригинала = path.join(__dirname, '..', 'js', 'рейтинг-экран.js');

if (флагСломатьЗаголовок) {
  запуститьСломанныйЗаголовок();
} else if (флагСломатьПорядок) {
  запуститьСломанныйПорядок();
} else {
  /* Чистый прогон */
  const провалов = прогнать(путьОригинала);
  process.exit(провалов > 0 ? 1 : 0);
}

/**
 * Основная функция прогона: требует модуль по пути и гонит все проверки.
 * Возвращает число провалов.
 */
function прогнать(путьМодуля) {
  /* Очищаем кэш, чтобы require загрузил свежую версию */
  delete require.cache[path.resolve(путьМодуля)];

  const требование = require(path.resolve(путьМодуля));
  const видПоОтвету = требование.видПоОтвету;
  const заголовокРейтинга = требование.заголовокРейтинга;
  const подписьВыбораИгры = требование.подписьВыбораИгры;
  const пунктыПанелиИгр = требование.пунктыПанелиИгр;

  let проверокВсего = 0;
  let ошибок = 0;

  function проверить(название, условие) {
    проверокВсего += 1;
    if (!условие) {
      ошибок += 1;
      console.log('НЕ ПРОШЛО: ' + название);
    }
  }

  /* Проверяем, что пунктыПанелиИгр есть и работает */
  if (typeof пунктыПанелиИгр !== 'function') {
    console.log('ОШИБКА: функция пунктыПанелиИгр не экспортируется');
    return 1;
  }

  let пункты = [];
  try {
    пункты = пунктыПанелиИгр();
  } catch (сбой) {
    console.log('ОШИБКА: пунктыПанелиИгр() упала: ' + сбой.message);
    return 1;
  }

  if (!Array.isArray(пункты) || пункты.length === 0) {
    console.log('ОШИБКА: пунктыПанелиИгр() должна возвращать непустой массив');
    return 1;
  }

  /* Наборы ответов, которые встречает функция в жизни. Мусорные и пустые
     значения — специально: сервер может ответить чем угодно. */
  const ОТВЕТЫ = [
    { имя: 'беда с адресом', ответ: { беда: 'нет-адреса', данные: null } },
    { имя: 'плохой адрес', ответ: { беда: 'плохой-адрес', данные: null } },
    { имя: 'сервер не отвечает', ответ: { беда: 'связь', данные: null } },
    { имя: 'не в телеграме', ответ: { беда: null, данные: { узналиВас: false, причина: 'тест' } } },
    { имя: 'таблица совсем пустая', ответ: { беда: null, данные: { узналиВас: true, всего: 0, верхушка: [], вокругМеня: [] } } },
    { имя: 'таблица есть, меня в ней нет', ответ: { беда: null, данные: {
      узналиВас: true, всего: 3, яВТаблице: false,
      верхушка: [{ место: 1, имя: 'Игрок', очки: 10, побед: 1, партий: 1 }], вокругМеня: []
    } } },
    { имя: 'я в таблице', ответ: { беда: null, данные: {
      узналиВас: true, всего: 3, яВТаблице: true,
      я: { место: 2, имя: 'Я', очки: 5, побед: 1, партий: 2, этоЯ: true },
      верхушка: [{ место: 1, имя: 'Лидер', очки: 10, побед: 2, партий: 2 }],
      вокругМеня: [{ место: 2, имя: 'Я', очки: 5, побед: 1, партий: 2, этоЯ: true }]
    } } },
    { имя: 'сервер не знает про силу', ответ: { беда: null, данные: { узналиВас: true, всего: 1, яВТаблице: false, верхушка: [], вокругМеня: [] } } },
    { имя: 'сервер прислал мусор вместо данных', ответ: { беда: null, данные: 'мусор' } },
    { имя: 'сервер вообще ничего не прислал', ответ: null },
  ];

  const МЕРЫ = ['очки', 'сила'];
  const ИГРЫ = ['дурак', 'шашки', 'шахматы', 'нарды'];

  /* Смысл двойного цикла: экран один и тот же на все четыре игры, но
     штаб просил проверить именно то, что новые игры (шахматы, нарды)
     не ломают функцию, которая раньше знала только дурака и шашки. */
  for (const игра of ИГРЫ) {
    for (const мера of МЕРЫ) {
      for (const { имя, ответ } of ОТВЕТЫ) {
        let вид;
        let упало = false;
        try {
          вид = видПоОтвету(ответ, мера);
        } catch (сбой) {
          упало = true;
          ошибок += 1;
          проверокВсего += 1;
          console.log('УПАЛО: игра=' + игра + ', мера=' + мера + ', случай=«' + имя + '»: ' + сбой.message);
        }
        if (упало) continue;

        проверить('игра=' + игра + ' мера=' + мера + ' случай=«' + имя + '»: есть поле «случай»',
          typeof вид.случай === 'string' && вид.случай.length > 0);
        проверить('игра=' + игра + ' мера=' + мера + ' случай=«' + имя + '»: «строки» это массив',
          Array.isArray(вид.строки));
        проверить('игра=' + игра + ' мера=' + мера + ' случай=«' + имя + '»: «лидеры» это массив',
          Array.isArray(вид.лидеры));
        /* Каждая строка таблицы обязана быть безопасной для показа текстом:
           имя — строка, место и очки — число или null, никогда не «NaN». */
        for (const строка of вид.строки.concat(вид.лидеры)) {
          проверить('игра=' + игра + ' случай=«' + имя + '»: имя строки — не пустая строка',
            typeof строка.имя === 'string' && строка.имя.length > 0);
          if ('место' in строка) {
            проверить('игра=' + игра + ' случай=«' + имя + '»: место — число или null, не NaN',
              строка.место === null || (typeof строка.место === 'number' && isFinite(строка.место)));
          }
        }
      }
    }
  }

  /* =====================================================================
     Новые проверки шага 5 плана «Рейтинг по макету»: пункт «Все игры»
     ===================================================================== */

  console.log('');
  console.log('Проверяю новый пункт «Все игры»...');

  /* 1. Чистые функции на всех пяти значениях плюс мусор */
  const КЛЮЧИ_РЕЕСТРА = пункты.map(п => п.ключ);
  const МУСОР = ['', null, 'незнакомая-игра', undefined];

  /* Словарь подписей из реестра — для проверки содержимого */
  const реестрДанных = {};
  for (const пункт of пункты) {
    реестрДанных[пункт.ключ] = пункт.подпись;
  }

  /* Заголовок для функции заголовокРейтинга */
  const заголовкиПоКлючу = {};
  for (const ключ of КЛЮЧИ_РЕЕСТРА) {
    let заголовок = '';
    let упало = false;
    try {
      заголовок = заголовокРейтинга(ключ);
    } catch (сбой) {
      упало = true;
      ошибок += 1;
      проверокВсего += 1;
      console.log('УПАЛО: заголовокРейтинга(«' + ключ + '»): ' + сбой.message);
    }
    if (!упало) {
      заголовкиПоКлючу[ключ] = заголовок;
      проверить('заголовокРейтинга(«' + ключ + '»): не пустая строка',
        typeof заголовок === 'string' && заголовок.length > 0);

      /* Усиленная проверка: содержимое должно быть осмысленным */
      if (ключ === 'все') {
        проверить('заголовокРейтинга(«все»): не содержит названия ни одной игры',
          !КЛЮЧИ_РЕЕСТРА.some(к => к !== 'все' && заголовок.toLowerCase().includes(реестрДанных[к].toLowerCase())));
      }
    }
  }

  /* Проверяем, что заголовки разные для разных ключей (укрепляет проверку от «всегда одна строка») */
  проверить('пунктыПанелиИгр(): в перечне больше одного пункта',
    КЛЮЧИ_РЕЕСТРА.length > 1);
  if (КЛЮЧИ_РЕЕСТРА.length > 1) {
    const уникальныеЗаголовки = new Set(Object.values(заголовкиПоКлючу));
    проверить('Заголовки разные для разных ключей (не одна и та же строка)',
      уникальныеЗаголовки.size > 1);
  }

  /* Мусор должен давать заголовок, а не падать */
  for (const мусорное of МУСОР) {
    let заголовок = '';
    let упало = false;
    try {
      заголовок = заголовокРейтинга(мусорное);
    } catch (сбой) {
      упало = true;
      ошибок += 1;
      проверокВсего += 1;
      console.log('УПАЛО: заголовокРейтинга на мусоре («' + мусорное + '»): ' + сбой.message);
    }
    if (!упало) {
      проверить('заголовокРейтинга(мусор): не падает и не пустая строка',
        typeof заголовок === 'string' && заголовок.length > 0);
    }
  }

  /* Подпись для функции подписьВыбораИгры */
  for (const ключ of КЛЮЧИ_РЕЕСТРА) {
    let подпись = '';
    let упало = false;
    try {
      подпись = подписьВыбораИгры(ключ);
    } catch (сбой) {
      упало = true;
      ошибок += 1;
      проверокВсего += 1;
      console.log('УПАЛО: подписьВыбораИгры(«' + ключ + '»): ' + сбой.message);
    }
    if (!упало) {
      проверить('подписьВыбораИгры(«' + ключ + '»): не пустая строка',
        typeof подпись === 'string' && подпись.length > 0);
    }
  }

  /* Мусор должен давать подпись, а не падать */
  for (const мусорное of МУСОР) {
    let подпись = '';
    let упало = false;
    try {
      подпись = подписьВыбораИгры(мусорное);
    } catch (сбой) {
      упало = true;
      ошибок += 1;
      проверокВсего += 1;
      console.log('УПАЛО: подписьВыбораИгры на мусоре («' + мусорное + '»): ' + сбой.message);
    }
    if (!упало) {
      проверить('подписьВыбораИгры(мусор): не падает и не пустая строка',
        typeof подпись === 'string' && подпись.length > 0);
    }
  }

  /* 2. Ответ «все игры» с null-полями должен разбираться без ошибок */
  const ответВсеИгры = {
    беда: null,
    данные: {
      узналиВас: true,
      всего: 1,
      яВТаблице: true,
      я: { место: 1, имя: 'Я Вездесущий', очки: 42, побед: 10, партий: 20, этоЯ: true, сила: null, поПравилу: null, поСоставу: null },
      верхушка: [
        { место: 1, имя: 'Лидер Времени', очки: 100, побед: 50, партий: 100, сила: null, поПравилу: null, поСоставу: null }
      ],
      вокругМеня: []
    }
  };

  let видВсе = null;
  try {
    видВсе = видПоОтвету(ответВсеИгры, 'очки');
  } catch (сбой) {
    ошибок += 1;
    проверокВсего += 1;
    console.log('УПАЛО: видПоОтвету на ответе «все игры» с мерой очки: ' + сбой.message);
  }

  if (видВсе) {
    проверить('видПоОтвету(все игры, очки): есть поле «случай»',
      typeof видВсе.случай === 'string' && видВсе.случай.length > 0);
    проверить('видПоОтвету(все игры, очки): «строки» это массив',
      Array.isArray(видВсе.строки));
    проверить('видПоОтвету(все игры, очки): «лидеры» это массив',
      Array.isArray(видВсе.лидеры));

    /* Проверить, что числа прочитаны правильно, мусора нет */
    for (const строка of видВсе.строки.concat(видВсе.лидеры)) {
      проверить('видПоОтвету(все игры): имя — не пустая строка',
        typeof строка.имя === 'string' && строка.имя.length > 0);
      if ('место' in строка) {
        проверить('видПоОтвету(все игры): место — число или null, не NaN',
          строка.место === null || (typeof строка.место === 'number' && isFinite(строка.место)));
      }
      if ('очки' in строка) {
        проверить('видПоОтвету(все игры): очки — число или null, не NaN',
          строка.очки === null || (typeof строка.очки === 'number' && isFinite(строка.очки)));
      }
    }
  }

  /* 3. Мера «сила» при ответе «все игры» — проверяем, что честная ошибка,
     а не выдуманное число. */
  let видВсеСила = null;
  try {
    видВсеСила = видПоОтвету(ответВсеИгры, 'сила');
  } catch (сбой) {
    ошибок += 1;
    проверокВсего += 1;
    console.log('УПАЛО: видПоОтвету на ответе «все игры» с мерой сила: ' + сбой.message);
  }

  if (видВсеСила) {
    проверить('видПоОтвету(все игры, сила): возвращает непустой случай',
      typeof видВсеСила.случай === 'string' && видВсеСила.случай.length > 0);
  }

  /* 4. Порядок в реестре: «Все игры» должен быть первым.
     Читаем из функции пунктыПанелиИгр(), не из исходника. */
  проверить('пунктыПанелиИгр(): перечень не пустой',
    пункты.length > 0);
  if (пункты.length > 0) {
    проверить('Первый пункт панели игр имеет ключ «все»',
      пункты[0].ключ === 'все');
  }

  /* Выводим итог и возвращаем число провалов */
  console.log('');
  console.log('Итого проверок: ' + проверокВсего + ', провалов: ' + ошибок);

  return ошибок;
}

/**
 * Ломающий запуск 1: портит заголовок.
 * В копии меняет 'Общий рейтинг' на 'Рейтинг Дурака'.
 */
function запуститьСломанныйЗаголовок() {
  console.log('Ломающий запуск --сломать-заголовок');
  console.log('Портю копию: заголовок для "все" становится "Рейтинг Дурака"');
  console.log('');

  const копияПапка = path.join(os.tmpdir(), 'games-тест-' + Date.now());
  const копияПуть = path.join(копияПапка, 'рейтинг-экран.js');

  if (!fs.existsSync(копияПапка)) {
    fs.mkdirSync(копияПапка, { recursive: true });
  }

  let содержимое = fs.readFileSync(путьОригинала, 'utf8');
  const искомаяСтрока = "if (игра === 'все') return 'Общий рейтинг';";
  const замена = "if (игра === 'все') return 'Рейтинг Дурака';";

  if (!содержимое.includes(искомаяСтрока)) {
    console.log('ОШИБКА: поломка не применилась: в js/рейтинг-экран.js не найдена строка:');
    console.log('  ' + искомаяСтрока);
    process.exit(1);
  }

  содержимое = содержимое.replace(искомаяСтрока, замена);

  /* Проверяем, что замена действительно применилась */
  if (!содержимое.includes(замена)) {
    console.log('ОШИБКА: замена не применилась (внутренняя ошибка)');
    process.exit(1);
  }

  fs.writeFileSync(копияПуть, содержимое, 'utf8');

  const провалов = прогнать(копияПуть);

  /* Очистка */
  try {
    fs.unlinkSync(копияПуть);
    fs.rmdirSync(копияПапка);
  } catch (е) {
    /* Игнорируем */
  }

  process.exit(провалов > 0 ? 1 : 0);
}

/**
 * Ломающий запуск 2: портит порядок пунктов.
 * В копии переставляет первые две записи в РЕЕСТР_ИГР.
 */
function запуститьСломанныйПорядок() {
  console.log('Ломающий запуск --сломать-порядок-пунктов');
  console.log('Портю копию: переставляю первые две записи РЕЕСТР_ИГР');
  console.log('');

  const копияПапка = path.join(os.tmpdir(), 'games-тест-' + Date.now());
  const копияПуть = path.join(копияПапка, 'рейтинг-экран.js');

  if (!fs.existsSync(копияПапка)) {
    fs.mkdirSync(копияПапка, { recursive: true });
  }

  let содержимое = fs.readFileSync(путьОригинала, 'utf8');

  /* Ищем блок РЕЕСТР_ИГР с двумя первыми записями */
  const искомыйБлок = "const РЕЕСТР_ИГР = [\n    { ключ: 'все', подпись: 'Все игры' },\n    { ключ: 'дурак', подпись: 'Дурак'";
  const заменаБлок = "const РЕЕСТР_ИГР = [\n    { ключ: 'дурак', подпись: 'Дурак'";

  if (!содержимое.includes(искомыйБлок)) {
    console.log('ОШИБКА: поломка не применилась: в js/рейтинг-экран.js не найдена строка:');
    console.log('  ' + искомыйБлок.substring(0, 60) + '...');
    process.exit(1);
  }

  /* Более простой подход: переставить две первые записи в массиве */
  const регРеестр = /const РЕЕСТР_ИГР = \[\s*\{ ключ: 'все'[\s\S]*?\},\s*\{ ключ: 'дурак'[\s\S]*?\},/;
  const совпадение = содержимое.match(регРеестр);

  if (!совпадение) {
    console.log('ОШИБКА: поломка не применилась: не найдена структура РЕЕСТР_ИГР');
    process.exit(1);
  }

  /* Заменяем: убираем запись 'все' и переставляем */
  содержимое = содержимое.replace(
    /const РЕЕСТР_ИГР = \[\s*\{ ключ: 'все', подпись: 'Все игры' },\s*\{ ключ: 'дурак'/,
    "const РЕЕСТР_ИГР = [\n    { ключ: 'дурак'"
  );

  /* Добавляем 'все' вторым после дурака */
  содержимое = содержимое.replace(
    /{ ключ: 'дурак', подпись: 'Дурак', родительный: 'Дурака', предложный: 'Дураке' },/,
    "{ ключ: 'дурак', подпись: 'Дурак', родительный: 'Дурака', предложный: 'Дураке' },\n    { ключ: 'все', подпись: 'Все игры' },"
  );

  /* Проверяем, что первый пункт теперь 'дурак' */
  if (содержимое.indexOf("{ ключ: 'все'") < содержимое.indexOf("{ ключ: 'дурак'")) {
    console.log('ОШИБКА: замена не применилась правильно');
    process.exit(1);
  }

  fs.writeFileSync(копияПуть, содержимое, 'utf8');

  const провалов = прогнать(копияПуть);

  /* Очистка */
  try {
    fs.unlinkSync(копияПуть);
    fs.rmdirSync(копияПапка);
  } catch (е) {
    /* Игнорируем */
  }

  process.exit(провалов > 0 ? 1 : 0);
}
