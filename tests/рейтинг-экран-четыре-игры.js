/**
 * Ломающий запуск 8 (ревью партии 6, пункт 1): переставляет порядок веток
 * ВНУТРИ профильПоОтвету() — блок «if (профильОтказанСервером)» встаёт
 * ВЫШЕ блока «if (данные.узналиВас !== true)». Проверяет, что ответ
 * с узналиВас=false и ок=false разом всё равно идёт в честные нули,
 * а не в «отказ сервера».
 */
function запуститьСломанныйПорядокВетокПрофиля() {
  console.log('Ломающий запуск --сломать-порядок-веток-профиля');
  console.log('Портю копию: в профильПоОтвету() переставляю «if (профильОтказанСервером)»');
  console.log('ВЫШЕ «if (данные.узналиВас !== true)»');
  console.log('');

  const копияПапка = path.join(os.tmpdir(), 'games-тест-порядок-веток-профиля-' + Date.now());
  const копияПуть = path.join(копияПапка, 'рейтинг-экран.js');

  if (!fs.existsSync(копияПапка)) {
    fs.mkdirSync(копияПапка, { recursive: true });
  }

  let содержимое = fs.readFileSync(путьОригинала, 'utf8');

  /* Ищем блок «узналиВас !== true» внутри профильПоОтвету */
  const регУзналиВас = /if \(данные\.узналиВас !== true\) \{\s*return \{\s*беда: null, узналиВас: false, место: null, всего: null,\s*очки: null, движение: null, сдвиг: null, поИграм: null\s*\};\s*\}/;
  const блокУзналиВас = содержимое.match(регУзналиВас);

  if (!блокУзналиВас) {
    console.log('ОШИБКА: не найдена ветка «if (данные.узналиВас !== true)» в профильПоОтвету');
    process.exit(1);
  }

  /* Ищем блок «профильОтказанСервером» (объявление переменной + if) */
  const регОтказ = /const профильОтказанСервером = данные\.ок === false;\s*if \(профильОтказанСервером\) \{\s*return \{[\s\S]*?поИграм: null\s*\};\s*\}/;
  const блокОтказ = содержимое.match(регОтказ);

  if (!блокОтказ) {
    console.log('ОШИБКА: не найдена ветка «профильОтказанСервером» в профильПоОтвету');
    process.exit(1);
  }

  /* Убираем оба блока и вставляем в обратном порядке — отказ сервера
     первым, «не узнали» вторым. */
  содержимое = содержимое.replace(регУзналиВас, '');
  содержимое = содержимое.replace(регОтказ, '');

  /* Якорная строка «const данные = итог.данные || {};» встречается в
     файле не один раз (решение(), профильПоОтвету() и ещё одна функция) —
     ищем её только ПОСЛЕ начала самой профильПоОтвету, иначе вставка
     уедет в чужую функцию и сломает вообще всё подряд. */
  const началоФункции = содержимое.indexOf('function профильПоОтвету(ответ) {');
  if (началоФункции === -1) {
    console.log('ОШИБКА: не найдено начало функции профильПоОтвету');
    process.exit(1);
  }
  const якорь = 'const данные = итог.данные || {};';
  const позицияЯкоря = содержимое.indexOf(якорь, началоФункции);
  if (позицияЯкоря === -1) {
    console.log('ОШИБКА: не найдена якорная точка «const данные = итог.данные || {};» внутри профильПоОтвету');
    process.exit(1);
  }
  const концаСтроки = содержимое.indexOf('\n', позицияЯкоря) + 1;
  const вставка = блокОтказ[0] + '\n' + блокУзналиВас[0];
  содержимое = содержимое.slice(0, концаСтроки) + вставка + '\n' + содержимое.slice(концаСтроки);

  fs.writeFileSync(копияПуть, содержимое, 'utf8');

  console.log('Порядок изменён. Запускаю те же проверки...');
  console.log('Пункты, которые ДОЛЖНЫ покраснеть:');
  console.log('  - профильПоОтвету: узналиВас=false и ок=false разом — беда === null (не «отказ сервера»)');
  console.log('  - профильПоОтвету: узналиВас=false и ок=false разом — узналиВас === false');
  console.log('');

  const провалов = прогнать(копияПуть);

  /* Очистка */
  try {
    fs.unlinkSync(копияПуть);
    fs.rmdirSync(копияПапка);
  } catch (е) {
    /* Игнорируем */
  }

  if (провалов === 0) {
    console.log('');
    console.log('ПРОВЕРКА СЛЕПАЯ: проверка порядка веток профиля не покраснела!');
    console.log('Это значит, что перестановка веток не повлияла на результаты.');
    process.exit(1);
  }

  process.exit(провалов > 0 ? 1 : 0);
}

