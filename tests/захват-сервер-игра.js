function сделатьКопию() {
  const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-сервер-'));
  const ПАПКА_ДАННЫХ = path.join(КОРЕНЬ, 'server', 'данные');
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(врем, 'server'), {
    recursive: true,
    // Данные игроков проверке не нужны — не копируем.
    filter: function (откуда) { return откуда !== ПАПКА_ДАННЫХ && !откуда.startsWith(ПАПКА_ДАННЫХ + path.sep); }
  });
  fs.cpSync(path.join(КОРЕНЬ, 'js'), path.join(врем, 'js'), { recursive: true });
  return врем;
}

/** Номера пунктов, у которых в выводе есть красная строка. */
function красныеПункты(вывод) {
  const пункты = new Set();
  вывод.split(/\r?\n/).forEach(function (строка) {
    const м = строка.match(/ПЛОХО — \((\d)\)/);
    if (м) пункты.add(м[1]);
  });
  return пункты;
}

function ломающийЗапуск() {
  console.log('=== Ломающий запуск: порченые копии захват.js ===');
  let плохих = 0;
  ПОРЧИ.forEach(function (порча) {
    console.log('\n--- Порча: ' + порча.имя + ' (обязан покраснеть пункт (' + порча.краснеет + ')) ---');
    const папка = сделатьКопию();
    try {
      const файл = path.join(папка, 'server', 'игры', 'захват.js');
      let текст = fs.readFileSync(файл, 'utf8').replace(/\r\n/g, '\n');
      for (const [было, стало] of порча.замены) {
        const найдено = текст.split(было).length - 1;
        if (найдено !== 1) {
          console.log('  ПЛОХО — строка для порчи нашлась ' + найдено + ' раз(а), нужно ровно 1: ' + JSON.stringify(было));
          плохих++;
          return;
        }
        текст = текст.split(было).join(стало);
      }
      fs.writeFileSync(файл, текст, 'utf8');
      console.log('  копия: ' + папка);
      let вывод = '';
      let код = 0;
      try {
        вывод = execFileSync(process.execPath, [__filename, '--папка', папка], { encoding: 'utf8', stdio: 'pipe' });
      } catch (сбой) {
        вывод = String(сбой.stdout || '') + String(сбой.stderr || '');
        код = сбой.status;
      }
      const красные = красныеПункты(вывод);
      const итог = (вывод.match(/Итого проверок: \d+, провалов: \d+/) || ['нет строки итога'])[0];
      console.log('  ' + итог + ', код выхода ' + код + ', красные пункты: ' + (красные.size ? Array.from(красные).map(function (н) { return '(' + н + ')'; }).join(' ') : 'нет'));
      const свойКрасный = красные.has(порча.краснеет);
      const чужихНет = Array.from(красные).every(function (н) { return н === порча.краснеет; });
      if (свойКрасный && чужихНет && код === 1) {
        console.log('  ок    — покраснел пункт (' + порча.краснеет + '), остальные зелёные');
      } else {
        плохих++;
        console.log('  ПЛОХО — ожидали красный только (' + порча.краснеет + ') и код 1');
        вывод.split(/\r?\n/).filter(function (с) { return с.indexOf('ПЛОХО') !== -1; })
          .forEach(function (с) { console.log('      ' + с.trim()); });
      }
    } finally {
      fs.rmSync(папка, { recursive: true, force: true });
    }
  });
  console.log('\nИтого порч: ' + ПОРЧИ.length + ', не пойманных: ' + плохих);
  if (плохих > 0) process.exitCode = 1;
  else console.log('Ломающий запуск покраснел на каждой порче, как и должен.');
}

