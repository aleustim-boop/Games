/** Свой генератор случая: прогон повторяется слово в слово. */
function генератор(зерно) {
  let а = зерно >>> 0;
  return function () {
    а = (а + 0x6D2B79F5) >>> 0;
    let т = а;
    т = Math.imul(т ^ (т >>> 15), т | 1);
    т ^= т + Math.imul(т ^ (т >>> 7), т | 61);
    return ((т ^ (т >>> 14)) >>> 0) / 4294967296;
  };
}

