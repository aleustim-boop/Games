  проверить(п.результат === остаётся, '(4) результат = оставшееся место');
  проверить(Array.isArray(п.проигравшие) && п.проигравшие.length === 1 && п.проигравшие[0] === сдаётся, '(4) проигравшие = сдавшийся');
