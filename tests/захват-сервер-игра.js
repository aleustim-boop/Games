/* Тот же порядок вызовов, что у комнаты для стола на 3+ места
   (server/комнаты.js, послатьЗнакВнимания): номер по каталогу игры,
   потом «бросок ли», бросок без адресата — отказ. */
function решениеОЗнаке(знаки, номер, цель) {
  if (!знаки.этоЗнак(номер)) return 'Такого смайлика нет';
  if (знаки.этоБросок(номер) && !цель) return 'Выберите, в кого бросить';
  return 'принято';
}

function проверитьДоговорИгры(Игра, откуда) {
  console.log('\n--- (1) Договор реестра ---');
  let ошибка = null;
  try { реестр.проверитьДоговор(Игра, откуда); } catch (e) { ошибка = e.message; }
  проверить(ошибка === null, '(1) проверитьДоговор из server/игры/реестр.js принимает игру' + (ошибка ? ' — ' + ошибка : ''));
  проверить(Игра.имя === 'захват', '(1) имя «захват»');
  проверить(!!Игра.мест && Игра.мест.мин === 2 && Игра.мест.макс === 6 && Игра.мест.впарах === 0,
    '(1) мест { мин: 2, макс: 6, впарах: 0 }');
  проверить(Игра.сдачаВыбывает === true, '(1) сдачаВыбывает: true');
  проверить(!!Игра.темпБота && Number.isFinite(Игра.темпБота.обычный) && Number.isFinite(Игра.темпБота.внеОчереди),
    '(1) темпБота — числа');
  проверить(typeof Игра.напарник === 'function' && Игра.напарник(['человек', 'бот'], 'человек', 4) === null,
    '(1) напарник → null');
  проверить(typeof Игра.вИгре === 'function', '(1) вИгре есть');

  const знаки = Игра.знаки || {};
  проверить(typeof знаки.голосБота === 'function' && знаки.голосБота({ событие: 'готово' }) === null,
    '(1) знаки.голосБота → null (боты молчат)');
  проверить(typeof знаки.сколько === 'function' && знаки.сколько() === ЗнакиЗахвата.сколько(),
    '(1) знаки — каталог js/захват-знаки.js (' + ЗнакиЗахвата.сколько() + ' номеров)');
  const перваяФраза = ЗнакиЗахвата.ЭМОЦИИ.length;
  const первыйБросок = перваяФраза + ЗнакиЗахвата.ФРАЗЫ.length;
  проверить(ЗнакиЗахвата.ФРАЗЫ.length === 8 && первыйБросок === 20, '(1) у «Захвата» 8 фраз, первый бросок — № 20');
  let фразыНеБроски = typeof знаки.этоЗнак === 'function' && typeof знаки.этоБросок === 'function';
  for (let н = перваяФраза; фразыНеБроски && н < первыйБросок; н++) {
    if (!знаки.этоЗнак(н) || знаки.этоБросок(н)) фразыНеБроски = false;
  }
  проверить(фразыНеБроски, '(1) № ' + перваяФраза + '–' + (первыйБросок - 1) + ' — фразы, не броски');
  проверить(typeof знаки.этоБросок === 'function' && знаки.этоБросок(20) === true, '(1) № 20 — бросок');
  проверить(ЗнакиДеберца.этоБросок(20) === false,
    '(1) у деберца № 20 — не бросок (каталог деберца на месте нашего был бы ошибкой)');
  if (typeof знаки.этоЗнак === 'function' && typeof знаки.этоБросок === 'function') {
    проверить(решениеОЗнаке(знаки, 20, null) === 'Выберите, в кого бросить',
      '(1) бросок № 20 без адресата — отказ «Выберите, в кого бросить»');
    проверить(решениеОЗнаке(знаки, 19, null) === 'принято', '(1) фраза № 19 без адресата — летит всему столу');
    проверить(решениеОЗнаке(знаки, ЗнакиЗахвата.сколько(), null) === 'Такого смайлика нет',
      '(1) номер за концом каталога — «Такого смайлика нет»');
  } else {
    проверить(false, '(1) у каталога знаков нет этоЗнак/этоБросок');
  }

  /* Вид на свежей партии: карта, раунд, ✓ — и ни одного внутреннего имени места. */
  подготовитьИгру(Игра, ЗЕРНО);
  const игроки = МЕСТА.slice(0, 3);
  let партия = null;
  try { партия = Игра.раздать(игроки[0], { игроки: игроки, люди: [игроки[0]], хозяин: игроки[0] }); } catch (e) { /* ниже */ }
  проверить(!!партия && партия.завершена === false && партия.раунд === 1, '(1) раздать даёт партию в первом раунде');
  if (!партия) return;
  проверить(Игра.чейХод(партия) === null, '(1) чейХод → null (очереди нет)');
  проверить(партия.началась === часы, '(1) партия.началась — часы сервера');
  проверить(партия.секундНаРаунд === 60, '(1) время раунда без настройки — 60 с');
  const быстрая = Игра.раздать(игроки[0], { игроки: игроки, лимитСекундНаХод: 40 });
  const странная = Игра.раздать(игроки[0], { игроки: игроки, лимитСекундНаХод: 45 });
  проверить(быстрая.секундНаРаунд === 40 && странная.секундНаРаунд === 60, '(1) время раунда 40 → 40, 45 → 60');
  проверить(Array.isArray(партия.люди) && партия.люди.length === 1 && партия.люди[0] === игроки[0] && партия.сЛюдьми === true,
    '(1) настройки.люди доехали в партию');
  let вид = null;
  try { вид = Игра.видДляИгрока(партия, игроки[1], { код: 'ABCD' }); } catch (e) { /* ниже */ }
  проверить(!!вид && !!вид.захват && вид.захват.карта === партия.карта && вид.захват.раунд === 1 &&
    Array.isArray(вид.захват.игроки) && вид.захват.игроки.length === 3 && вид.захват.я === 2,
    '(1) вид: карта, раунд, мой номер и строки мест');
  if (вид) {
    const текст = JSON.stringify(вид);
    const внутренние = МЕСТА.filter(function (м) { return текст.indexOf('"' + м + '"') !== -1; });
    проверить(внутренние.length === 0, '(1) в виде нет внутренних имён мест' + (внутренние.length ? ': ' + внутренние.join(', ') : ''));
    проверить(текст.indexOf('черновик') === -1, '(1) в виде нет черновиков');
  }
}

/* =====================================================================
   (2) ПАРТИЯ ТРЁХ БОТОВ ДО КОНЦА
   ===================================================================== */
function сыгратьБотами(Игра, зерно, уровни) {
  подготовитьИгру(Игра, зерно);
  const игроки = МЕСТА.slice(0, 3);
  const партия = Игра.раздать(игроки[0], { игроки: игроки, люди: [], хозяин: игроки[0] });
  let раундов = 0;
  let готовоБотом = 0;
  let повторноеГотово = false;
  let всеСГалочкой = true;
  while (!партия.завершена && раундов < РАУНДОВ_НЕ_БОЛЬШЕ) {
    игроки.forEach(function (место, и) {
      const сделано = Игра.ходЗаБота(партия, место, уровни[и]);
      if (сделано) {
        готовоБотом++;
        if (Игра.ходЗаБота(партия, место, уровни[и]) !== null) повторноеГотово = true;
      }
    });
    /* ✓ смотрим в самой партии, не в виде: вид — пункт (1), и порча вида
       не должна ронять этот пункт. */
    const вИгре = игроки.filter(function (место) { return Игра.вИгре(партия, место); });
    if (!вИгре.length || !вИгре.every(function (место) { return партия.готовКто[место] === 'бот'; })) всеСГалочкой = false;
    часы += 10000;
    const разбор = Игра.разобратьРаунд(партия);
    if (!разбор || !разбор.принято) break;
    раундов++;
  }
  return { партия: партия, игроки: игроки, раундов: раундов, готовоБотом: готовоБотом,
    повторноеГотово: повторноеГотово, всеСГалочкой: всеСГалочкой };
}

function проверитьПартиюБотов(Игра) {
  console.log('\n--- (2) Партия трёх ботов через раздать и ходЗаБота ---');
  const наборы = [
    { зерно: ЗЕРНО, уровни: ['лёгкий', 'обычный', 'сложный'] },
    { зерно: ЗЕРНО + 1, уровни: ['обычный', 'обычный', 'обычный'] },
    { зерно: ЗЕРНО + 2, уровни: ['сложный', 'лёгкий', 'неизвестный'] }
  ];
  наборы.forEach(function (н) {
    let игра = null;
    let сбой = null;
    try { игра = сыгратьБотами(Игра, н.зерно, н.уровни); } catch (e) { сбой = e.message; }
    const подпись = '(2) зерно ' + н.зерно + ', уровни ' + н.уровни.join('/');
    if (!игра) { проверить(false, подпись + ': партия упала — ' + сбой); return; }
    const п = игра.партия;
    проверить(игра.раундов > 0 && игра.готовоБотом > 0, подпись + ': боты жали «Готово» (' + игра.готовоБотом + ' раз за ' + игра.раундов + ' раундов)');
    проверить(игра.всеСГалочкой, подпись + ': после ходов ботов у всех в игре ✓ «бот»');
    проверить(!игра.повторноеГотово, подпись + ': второй ход бота в том же раунде — null');
    проверить(п.завершена === true, подпись + ': партия.завершена');
    проверить(typeof п.результат === 'string' && игра.игроки.indexOf(п.результат) !== -1, подпись + ': результат — ключ места строкой');
    const остальные = игра.игроки.filter(function (к) { return к !== п.результат; }).sort();
    проверить(Array.isArray(п.проигравшие) && JSON.stringify(п.проигравшие.slice().sort()) === JSON.stringify(остальные),
      подпись + ': проигравшие — все остальные места');
    проверить(п.ничья === false, подпись + ': ничья: false');
    проверить(!!п.итог && Array.isArray(п.итог.места) && п.итог.места.length === 3 && п.итог.места[0].кто === п.результат &&
      typeof п.итог.причина === 'string', подпись + ': итог — места и причина, первое место = результат');
    проверить(Игра.ходЗаБота(п, игра.игроки[0], 'обычный') === null && Игра.разобратьРаунд(п).принято === false,
      подпись + ': после конца ни хода бота, ни разбора');
  });
}

