function значениеДовода(имя) {
  const и = process.argv.indexOf(имя);
  return и !== -1 && process.argv[и + 1] ? process.argv[и + 1] : null;
}

function обычныйЗапуск() {
  const папка = значениеДовода('--папка');
  const путь = папка
    ? path.join(папка, 'server', 'игры', 'захват.js')
    : path.join(КОРЕНЬ, 'server', 'игры', 'захват.js');
  console.log('=== «Захват» для сервера: договор и партия через него ===');
  if (папка) console.log('проверяем копию: ' + путь);
  let Игра = null;
  try { Игра = require(путь); } catch (e) { проверить(false, '(0) модуль загружается: ' + e.message); }
  if (Игра) {
    проверитьДоговорИгры(Игра, путь);
    проверитьПартиюБотов(Игра);
    проверитьОпоздавшего(Игра);
    проверитьСдачу(Игра);
  }
  console.log('\nИтого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
  if (всегоПроверок === 0) {
    console.log('ПЛОХО: не сделано ни одной проверки — она смотрит не туда');
    process.exitCode = 1;
    return;
  }
  if (провалов > 0) process.exitCode = 1;
}

