/* Поля «по случаю»: итог и отменена — только у оконченной партии, хозяеваДо и
   войскаДо — только после первого разбора. Когда именно они приходят, смотрит
   пункт (14); доПобеды приходит всегда (постоянное поле выше), его значение — tests/захват-сервер-войска-до.js. */
const ПОЛЯ_ПО_СЛУЧАЮ = ['итог', 'отменена', 'хозяеваДо', 'войскаДо'];
const ПОЛЯ_ИГРОКА = ['номер', 'имя', 'цвет', 'областей', 'очков', 'подкрепление', 'готов', 'выбыл', 'ушёл', 'сдался', 'этоБот', 'спит'];
/* Внутренние слова, которых в виде быть не должно ни в каком месте. */
const ТАЙНЫЕ_СЛОВА = ['"черновики"', 'готовКто', 'ботГотовВ', 'общийЗнак', 'знакОбщий', 'пропуск', 'разобранВ', '"люди"',
  'хозяеваДоРазбора', '"результат"'];

function обёрткаСтола(игроки, добавка) {
  return Object.assign({
    код: 'ABCD', этап: 'игра', версия: 7, номерСобытия: 3, событие: '',
    участники: игроки.map(function (к, и) { return { ключ: к, имя: 'Имя' + (и + 1), этоБот: и === игроки.length - 1 }; }),
    знакСырой: null
  }, добавка || {});
}

/* Сколько внутренних имён мест встретилось в тексте вида. */
function внутренниеИмена(вид) {
  const текст = JSON.stringify(вид);
  return МЕСТА.filter(function (м) { return текст.indexOf('"' + м + '"') !== -1; });
}

function проверитьЧистотуВида(вид, подпись) {
  проверить(!!вид && !!вид.захват, подпись + ': блок «захват» есть');
  if (!вид || !вид.захват) return;
  const лишние = Object.keys(вид.захват).filter(function (к) { return ПОЛЯ_ЗАХВАТА.indexOf(к) === -1 && ПОЛЯ_ПО_СЛУЧАЮ.indexOf(к) === -1; });
  const нет = ПОЛЯ_ЗАХВАТА.filter(function (к) { return !(к in вид.захват); });
  проверить(лишние.length === 0 && нет.length === 0,
    подпись + ': поля «захват» ровно по 15.3' + (лишние.length ? ', лишние: ' + лишние.join(', ') : '') + (нет.length ? ', нет: ' + нет.join(', ') : ''));
  const имена = внутренниеИмена(вид);
  проверить(имена.length === 0, подпись + ': внутренних имён мест нет' + (имена.length ? ' — ' + имена.join(', ') : ''));
  const текст = JSON.stringify(вид);
  const слова = ТАЙНЫЕ_СЛОВА.filter(function (с) { return текст.indexOf(с) !== -1; });
  проверить(слова.length === 0, подпись + ': внутренних полей нет' + (слова.length ? ' — ' + слова.join(', ') : ''));
}

function проверитьВид(Игра) {
  console.log('\n--- (11) Вид для игрока и тайна черновиков ---');
  подготовитьИгру(Игра, ЗЕРНО + 30);
  /* Места с пропуском (кресла 1, 3, 4): номер кресла в виде — не порядок в партии. */
  const игроки = [МЕСТА[0], МЕСТА[2], МЕСТА[3]];
  const [А, Б, В] = игроки;
  const кресло = function (ключ) { return МЕСТА.indexOf(ключ) + 1; };
  const п = Игра.раздать(А, { игроки: игроки, люди: [А, Б], хозяин: А });
  const обёртка = обёрткаСтола(игроки);
  обёртка.участники[1].спит = true;

  const видБДо = Игра.видДляИгрока(п, Б, обёртка);
  проверитьЧистотуВида(видБДо, '(11) свежая партия, вид Б');
  const з = видБДо.захват;
  проверить(з.я === кресло(Б) && з.я === 3 && з.карта === п.карта && з.раунд === 1 && з.всегоРаундов === п.всегоРаундов && з.мсДоКонца > 0,
    '(11) карта, раунд, всего раундов, мой номер, мс до конца');
  const хозяеваНомерами = п.хозяева.map(function (х) { return х === null ? null : МЕСТА.indexOf(х) + 1; });
  проверить(одинаково(з.хозяева, хозяеваНомерами) && одинаково(з.войска, п.войска),
    '(11) хозяева — номерами мест, войска — как в партии');
  проверить(з.столицы.length === 3 && з.столицы.every(function (с, и) {
    return с.хозяинНаСтарте === кресло(п.столицы[и].хозяинНаСтарте) && с.область === п.столицы[и].область;
  }) && з.столицы.map(function (с) { return с.хозяинНаСтарте; }).sort().join() === '1,3,4',
  '(11) столицы: область и номер кресла хозяина на старте (1, 3, 4)');
  const строкиВерны = з.игроки.length === 3 && з.игроки.every(function (с) {
    const лишних = Object.keys(с).filter(function (к) { return ПОЛЯ_ИГРОКА.indexOf(к) === -1; });
    return лишних.length === 0 && ПОЛЯ_ИГРОКА.every(function (к) { return к in с; });
  });
  проверить(строкиВерны, '(11) строки игроков — ровно поля 15.3');
  проверить(з.игроки.map(function (с) { return с.номер; }).join() === '1,3,4', '(11) игроки[].номер — номер кресла с единицы: 1, 3, 4');
  проверить(з.игроки[0].имя === 'Имя1' && з.игроки[1].спит === true && з.игроки[2].этоБот === true && з.игроки[0].этоБот === false &&
    з.игроки[2].цвет === 2 && з.игроки[0].подкрепление === п.подкрепление[А],
    '(11) имя, «спит», «этоБот», цвет и подкрепление — из комнаты и партии');
  проверить(з.моёПодкрепление.всего === п.подкрепление[Б] && Array.isArray(з.моёПодкрепление.края),
    '(11) моёПодкрепление: всего и разбивка');

  /* Случай 16 без комнаты: А шлёт 5 черновиков (3 принятых, 2 отказанных),
     вид Б побайтно тот же. Часы те же — иначе мсДоКонца разъедется сам. */
  const текстБДо = JSON.stringify(видБДо);
  const ответы = [
    Игра.принятьЧерновик(п, А, черновикВСтолицу(п, А, 1)),
    Игра.принятьЧерновик(п, А, черновикВСтолицу(п, А, п.подкрепление[А] + 5)),
    Игра.принятьЧерновик(п, А, черновикВСтолицу(п, А, 2)),
    Игра.принятьЧерновик(п, А, { раунд: 0, расстановка: {}, приказы: [] }),
    Игра.принятьЧерновик(п, А, черновикСПриказом(п, А) || черновикВСтолицу(п, А))
  ];
  const принято = ответы.filter(function (о) { return о.принято; }).length;
  проверить(принято === 3, '(11) из 5 черновиков А принято 3, отказано 2 (' + принято + ' принято)');
  проверить(JSON.stringify(Игра.видДляИгрока(п, Б, обёртка)) === текстБДо, '(11) вид Б после 5 черновиков А побайтно тот же');

  const видА = Игра.видДляИгрока(п, А, обёртка);
  проверитьЧистотуВида(видА, '(11) вид А с черновиком');
  проверить(одинаково({ расстановка: видА.захват.мойЧерновик.расстановка, приказы: видА.захват.мойЧерновик.приказы }, п.черновики[А]) &&
    видА.захват.мойЧерновик.составилБот === false, '(11) мойЧерновик у А — его черновик');
  проверить(одинаково(видБДо.захват.мойЧерновик, { расстановка: {}, приказы: [], составилБот: false }),
    '(11) мойЧерновик у Б — его (пустой), не черновик А');

  /* Черновик бота за спящего — с пометкой «составил бот», и только ему. */
  const видВДо = Игра.видДляИгрока(п, В, обёртка);
  Игра.ходЗаБота(п, Б, 'обычный');
  const видБ = Игра.видДляИгрока(п, Б, обёртка);
  проверить(видБ.захват.мойЧерновик.составилБот === true && видБ.захват.яГотов === true && видБ.захват.игроки[1].готов === true,
    '(11) спящему — черновик бота с пометкой «составил бот», ✓ видна');
  const видВ = Игра.видДляИгрока(п, В, обёртка);
  проверитьЧистотуВида(видВ, '(11) вид В, когда у А и Б есть черновики');
  /* Вид В до и после хода бота за Б — побайтно; отличается только ✓ Б в полосе. */
  const готовБДо = видВДо.захват.игроки[1].готов;
  const готовБПосле = видВ.захват.игроки[1].готов;
  const видВПослеБезГотов = копия(видВ);
  видВПослеБезГотов.захват.игроки[1].готов = готовБДо;
  проверить(готовБДо === false && готовБПосле === true && JSON.stringify(видВПослеБезГотов) === JSON.stringify(видВДо),
    '(11) у В нет следа черновика Б: вид до и после хода бота побайтно тот же, кроме игроки[1].готов');

  /* Ушёл и сдался — из партии. */
  правила().уйти(п, В);
  const видПослеУхода = Игра.видДляИгрока(п, А, обёртка);
  проверить(видПослеУхода.захват.игроки[2].ушёл === true && видПослеУхода.захват.игроки[2].сдался === false,
    '(11) ушедшее место — «ушёл»');

  /* После разбора: события последнего раунда с номерами мест вместо ключей. */
  Игра.сделатьХод(п, А, { действие: 'готово', раунд: 1 });
  Игра.ходЗаБота(п, В, 'обычный');
  часы += 10000;
  Игра.разобратьРаунд(п);
  const видРаунд2 = Игра.видДляИгрока(п, А, обёртка);
  проверитьЧистотуВида(видРаунд2, '(11) после разбора, вид А');
  const события = видРаунд2.захват.события;
  проверить(Array.isArray(события) && события.length > 0 && видРаунд2.захват.раундСобытий === 1 &&
    события.filter(function (с) { return 'кто' in с; }).every(function (с) { return Number.isInteger(с.кто); }),
    '(11) события раунда 1 — «кто» номером места (' + (события ? события.length : 0) + ' событий)');

  /* Конец партии: итог с номерами мест. */
  for (let р = 0; !п.завершена && р < РАУНДОВ_НЕ_БОЛЬШЕ; р++) {
    игроки.forEach(function (м) { Игра.ходЗаБота(п, м, 'обычный'); });
    часы += 10000;
    Игра.разобратьРаунд(п);
  }
  const видКонец = Игра.видДляИгрока(п, Б, обёртка);
  проверитьЧистотуВида(видКонец, '(11) окончённая партия, вид Б');
  const итог = видКонец.захват && видКонец.захват.итог;
  проверить(п.завершена === true && видКонец.завершена === true && !!итог && Array.isArray(итог.места) && итог.места.length === 3 &&
    итог.места.every(function (м) { return Number.isInteger(м.кто); }) && итог.победители.every(Number.isInteger) &&
    итог.места[0].кто === МЕСТА.indexOf(п.результат) + 1 && видКонец.захват.мсДоКонца === null,
    '(11) итог: места и победители номерами, первое место — результат, таймера нет');
}

