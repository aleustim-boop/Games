function сыгратьБотами(Игра, зерно, уровни) {
  подготовитьИгру(Игра, зерно);
  const игроки = МЕСТА.slice(0, 3);
  const партия = Игра.раздать(игроки[0], { игроки: игроки, люди: [], хозяин: игроки[0] });
  let раундов = 0;
  let готовоБотом = 0;
  let повторноеГотово = false;
  let всеСГалочкой = true;
  while (!партия.завершена && раундов < РАУНДОВ_НЕ_БОЛЬШЕ) {
    игроки.forEach(function (место, и) {
      const сделано = Игра.ходЗаБота(партия, место, уровни[и]);
      if (сделано) {
        готовоБотом++;
        if (Игра.ходЗаБота(партия, место, уровни[и]) !== null) повторноеГотово = true;
      }
    });
    /* ✓ смотрим в самой партии, не в виде: вид — пункт (1), и порча вида
       не должна ронять этот пункт. */
    const вИгре = игроки.filter(function (место) { return Игра.вИгре(партия, место); });
    if (!вИгре.length || !вИгре.every(function (место) { return партия.готовКто[место] === 'бот'; })) всеСГалочкой = false;
    часы += 10000;
    const разбор = Игра.разобратьРаунд(партия);
    if (!разбор || !разбор.принято) break;
    раундов++;
  }
  return { партия: партия, игроки: игроки, раундов: раундов, готовоБотом: готовоБотом,
    повторноеГотово: повторноеГотово, всеСГалочкой: всеСГалочкой };
}

function проверитьПартиюБотов(Игра) {
  console.log('\n--- (2) Партия трёх ботов через раздать и ходЗаБота ---');
  const наборы = [
    { зерно: ЗЕРНО, уровни: ['лёгкий', 'обычный', 'сложный'] },
    { зерно: ЗЕРНО + 1, уровни: ['обычный', 'обычный', 'обычный'] },
    { зерно: ЗЕРНО + 2, уровни: ['сложный', 'лёгкий', 'неизвестный'] }
  ];
  наборы.forEach(function (н) {
    let игра = null;
    let сбой = null;
    try { игра = сыгратьБотами(Игра, н.зерно, н.уровни); } catch (e) { сбой = e.message; }
    const подпись = '(2) зерно ' + н.зерно + ', уровни ' + н.уровни.join('/');
    if (!игра) { проверить(false, подпись + ': партия упала — ' + сбой); return; }
    const п = игра.партия;
    проверить(игра.раундов > 0 && игра.готовоБотом > 0, подпись + ': боты жали «Готово» (' + игра.готовоБотом + ' раз за ' + игра.раундов + ' раундов)');
    проверить(игра.всеСГалочкой, подпись + ': после ходов ботов у всех в игре ✓ «бот»');
    проверить(!игра.повторноеГотово, подпись + ': второй ход бота в том же раунде — null');
    проверить(п.завершена === true, подпись + ': партия.завершена');
    проверить(typeof п.результат === 'string' && игра.игроки.indexOf(п.результат) !== -1, подпись + ': результат — ключ места строкой');
    const остальные = игра.игроки.filter(function (к) { return к !== п.результат; }).sort();
    проверить(Array.isArray(п.проигравшие) && JSON.stringify(п.проигравшие.slice().sort()) === JSON.stringify(остальные),
      подпись + ': проигравшие — все остальные места');
    проверить(п.ничья === false, подпись + ': ничья: false');
    проверить(!!п.итог && Array.isArray(п.итог.места) && п.итог.места.length === 3 && п.итог.места[0].кто === п.результат &&
      typeof п.итог.причина === 'string', подпись + ': итог — места и причина, первое место = результат');
    проверить(Игра.ходЗаБота(п, игра.игроки[0], 'обычный') === null && Игра.разобратьРаунд(п).принято === false,
      подпись + ': после конца ни хода бота, ни разбора');
  });
}

