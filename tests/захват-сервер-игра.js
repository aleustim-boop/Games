function проверитьОпоздавшего(Игра) {
  console.log('\n--- (3) Опоздавшая дверь: «Раунд уже разыгран» ---');
  подготовитьИгру(Игра, ЗЕРНО + 3);
  const игроки = МЕСТА.slice(0, 3);
  const человек = игроки[0];
  const п = Игра.раздать(человек, { игроки: игроки, люди: [человек], хозяин: человек });

  const безНомера = Игра.сделатьХод(п, человек, { действие: 'готово' });
  проверить(безНомера.принято === false && безНомера.причина === 'Раунд уже разыгран' && безНомера.устарел === true,
    '(3) «готово» без номера раунда — отказ «Раунд уже разыгран»');
  const первое = Игра.сделатьХод(п, человек, { действие: 'готово', раунд: 1 });
  проверить(первое.принято === true && п.готовКто[человек] === 'сам', '(3) «готово» с верным номером — принято, ✓ «сам»');
  игроки.slice(1).forEach(function (место) { Игра.ходЗаБота(п, место, 'обычный'); });
  часы += 10000;
  const разбор = Игра.разобратьРаунд(п);
  проверить(разбор.принято === true && п.раунд === 2 && !п.готовКто[человек], '(3) раунд 1 разобран, открыт раунд 2, ✓ сброшены');

  const поздно = Игра.сделатьХод(п, человек, { действие: 'готово', раунд: 1 });
  проверить(поздно.принято === false && поздно.причина === 'Раунд уже разыгран' && поздно.устарел === true,
    '(3) «готово» с номером 1 в раунде 2 — отказ «Раунд уже разыгран», устарел: true');
  проверить(!п.готовКто[человек], '(3) после опоздавшего «готово» ✓ не поставлена');
  const поздноИзменить = Игра.сделатьХод(п, человек, { действие: 'изменить', раунд: 1 });
  проверить(поздноИзменить.принято === false && поздноИзменить.причина === 'Раунд уже разыгран',
    '(3) «изменить» со старым номером — тот же отказ');

  const есть = typeof Игра.устаревшийХод === 'function';
  проверить(есть, '(3) устаревшийХод — отдельный вызов игры');
  if (есть) {
    const до = JSON.stringify(п);
    проверить(Игра.устаревшийХод(п, человек, { действие: 'готово', раунд: 1 }).устарел === true, '(3) устаревшийХод: «готово» раунда 1 — устарел');
    проверить(Игра.устаревшийХод(п, человек, { раунд: 1, приказы: [] }).устарел === true, '(3) устаревшийХод: черновик раунда 1 — устарел');
    проверить(Игра.устаревшийХод(п, человек, { действие: 'готово', раунд: 2 }) === null, '(3) устаревшийХод: верный номер — null');
    проверить(Игра.устаревшийХод(п, человек, { действие: 'сдаться' }) === null, '(3) устаревшийХод: «сдаться» — null');
    проверить(JSON.stringify(п) === до, '(3) устаревшийХод партию не меняет');
  }
  const вовремя = Игра.сделатьХод(п, человек, { действие: 'готово', раунд: 2 });
  проверить(вовремя.принято === true, '(3) «готово» с номером 2 — принято');
  const снять = Игра.сделатьХод(п, человек, { действие: 'изменить', раунд: 2 });
  проверить(снять.принято === true && !п.готовКто[человек], '(3) «изменить» снимает ✓ и забывает «сам»');
}

