  полный.лишнее = 'мусор';
  const принят = Игра.принятьЧерновик(п, я, полный);
  const ждём = { расстановка: копия(полный.расстановка), приказы: [] };
  проверить(принят.принято === true && принят.причина === null && одинаково(п.черновики[я], ждём),
    '(5) черновик принят и сохранён (только расстановка и приказы, без «раунд» и лишних полей)');
  проверить(одинаково(принят.черновик, ждём) && принят.черновик !== п.черновики[я],
    '(5) в ответе — черновик как сохранён, копией, а не ссылкой на партию');
