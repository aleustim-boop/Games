function номерФразы(текст) {
  for (let н = 0; н < ЗнакиЗахвата.сколько(); н++) if (ЗнакиЗахвата.текст(н) === текст) return н;
  return -1;
}

function безВерсии(вид) {
  const копияВида = копия(вид);
  delete копияВида.версия;
  return JSON.stringify(копияВида);
}

function проверитьЗнаки(Игра) {
  console.log('\n--- (12) Знак внимания и фраза одному ---');
  подготовитьИгру(Игра, ЗЕРНО + 40);

  /* Своих часов для знаков у игры нет (решение штаба по ревью А9б, этап Б3ф):
     прежний общий знак и его свежесть даёт комната (обёртка.знакОбщийСырой).
     Срока знака в договоре игры быть не должно — иначе это вторые часы. */
  проверить(!('ЗНАК_ЖИВЁТ_МС' in Игра), '(12) у игры нет своего срока жизни знака (ЗНАК_ЖИВЁТ_МС)');

  /* Места с пропуском (кресла 1, 3, 4): «от» и «кому» в знаке — порядок места
     в партии с нуля (0, 1, 2), а не номер кресла. */
  const игроки = [МЕСТА[0], МЕСТА[2], МЕСТА[3]];
  const [Х, У, Ц] = игроки;
  const п = Игра.раздать(Х, { игроки: игроки, люди: игроки.slice(), хозяин: Х });
  const мир = номерФразы('Мир?');
  const лидер = номерФразы('Бьём лидера!');
  const бросок = ЗнакиЗахвата.ЭМОЦИИ.length + ЗнакиЗахвата.ФРАЗЫ.length;
  проверить(мир !== -1 && лидер !== -1 && ЗнакиЗахвата.этоБросок(бросок), '(12) в каталоге есть «Мир?», «Бьём лидера!» и бросок');
  let порядковый = 0;
  function знак(кто, номер, цель) {
    порядковый++;
    return { кто: кто, номер: номер, имя: 'Имя ' + кто, цель: цель || null, имяЦели: цель ? 'Имя ' + цель : null,
      когда: часы, порядковый: порядковый };
  }
  // общий — прежний общий знак, который комната даёт как ещё свежий (или null).
  function вид(место, сырой, версия, общий) {
    return Игра.видДляИгрока(п, место, обёрткаСтола(игроки, { знакСырой: сырой, знакОбщийСырой: общий || null, версия: версия || 7 }));
  }

  /* Фраза одному при пустом столе: у Ц до и после — побайтно то же. */
  const видЦДо = вид(Ц, null, 7);
  проверить(видЦДо.знакиВниманияЕсть === true && видЦДо.броскиЕсть === true, '(12) знакиВниманияЕсть и броскиЕсть');
  const мирУ = знак(Х, мир, У);
  const видХ = вид(Х, мирУ, 8);
  const видУ = вид(У, мирУ, 8);
  const видЦ = вид(Ц, мирУ, 8);
  проверить(!!видХ.знакВнимания && видХ.знакВнимания.номер === мир && видХ.знакВнимания.этоЯ === true &&
    видХ.знакВнимания.от === 0 && видХ.знакВнимания.кому === 1 && видХ.знакВнимания.цель === 'Имя ' + У,
    '(12) сказавший Х видит «Мир?»: от 0, кому 1, цель — имя У');
  проверить(!!видУ.знакВнимания && видУ.знакВнимания.номер === мир && видУ.знакВнимания.вМеня === true && видУ.знакВнимания.от === 0,
    '(12) адресат У видит «Мир?», «в меня», от = порядок места Х (0)');
  проверить(видУ.захват.я === 3 && видХ.захват.я === 1 && видЦ.захват.я === 4,
    '(12) при этом захват.я — номер кресла с единицы: 1, 3, 4');
  проверить(безВерсии(видЦ) === безВерсии(видЦДо), '(12) третий Ц: вид побайтно прежний (без поля версии) — фразы не было');

  /* Прежний общий знак: смайлик У. Потом «Мир?» Х → У — комната отдаёт
     смайлик как прежний общий, и у Ц остаётся смайлик. */
  const смайлик = знак(У, 0, null);
  const видЦСоСмайликом = вид(Ц, смайлик, 9, смайлик);
  проверить(!!видЦСоСмайликом.знакВнимания && видЦСоСмайликом.знакВнимания.номер === 0 && видЦСоСмайликом.знакВнимания.от === 1 &&
    видЦСоСмайликом.знакВнимания.кому === -1, '(12) смайлик У видят все: от = 1, кому = -1');
  const мир2 = знак(Х, мир, У);
  проверить(безВерсии(вид(Ц, мир2, 10, смайлик)) === безВерсии(видЦСоСмайликом),
    '(12) после «Мир?» Х → У у Ц вид побайтно прежний (виден смайлик от комнаты) — как будто фразы не было');
  проверить(вид(У, мир2, 10, смайлик).знакВнимания.номер === мир && вид(Х, мир2, 10, смайлик).знакВнимания.номер === мир,
    '(12) у адресата и сказавшего — «Мир?», а не смайлик');
  /* Смайлик протух — комната его больше не даёт: у Ц знака нет, как и без фразы.
     Игра сама ничего не помнит: тот же вид до и после показа смайлика. */
  проверить(!('знакВнимания' in вид(Ц, мир2, 11, null)),
    '(12) комната не дала прежний знак (протух) — у Ц знака нет: игра его не помнит сама');
  проверить(!('общийЗнак' in п) && Object.keys(п).every(function (к) { return к.indexOf('знак') === -1 && к.indexOf('Знак') === -1; }),
    '(12) партия не хранит знаков (у игры нет своей памяти о них): ' + Object.keys(п).filter(function (к) { return /знак/i.test(к); }).join(', '));
  /* Прежний «общий» от комнаты сам оказался фразой одному или новее фразы — его не берём. */
  const мирЦ = знак(Х, мир, Ц);
  const мир3 = знак(Х, мир, У);
  проверить(!('знакВнимания' in вид(Ц, мир3, 12, мирЦ)),
    '(12) прежний знак, который сам фраза одному, третьему не показывается');
  const новее = знак(У, 0, null);
  проверить(!('знакВнимания' in вид(Ц, мир3, 13, новее)),
    '(12) «прежний» знак новее фразы — не показывается (ошибка комнаты не утечёт мимо фразы)');

  /* Фраза всему столу и бросок с целью видят все. */
  const общая = знак(У, лидер, null);
  проверить(вид(Ц, общая).знакВнимания.номер === лидер && вид(Х, общая).знакВнимания.номер === лидер,
    '(12) «Бьём лидера!» видят все');
  const броскомВЦ = знак(Х, бросок, Ц);
  const третийВидитБросок = вид(У, броскомВЦ).знакВнимания;
  проверить(!!третийВидитБросок && третийВидитБросок.номер === бросок && третийВидитБросок.от === 0 && третийВидитБросок.кому === 2 &&
    третийВидитБросок.вМеня === false && вид(Ц, броскомВЦ).знакВнимания.вМеня === true,
    '(12) бросок Х в Ц видит и третий У: от 0, кому 2; у Ц — «в меня»');
  // Смотрим только сам знак: чистоту всего вида стережёт пункт (11).
  const знакУЦ = вид(Ц, броскомВЦ).знакВнимания;
  проверить(!!знакУЦ && внутренниеИмена(знакУЦ).length === 0 && JSON.stringify(знакУЦ).indexOf('когда') === -1,
    '(12) в знаке нет внутренних имён мест и времени');
}

