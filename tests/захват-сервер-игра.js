function проверитьСдачу(Игра) {
  console.log('\n--- (4) «Сдаться» вдвоём ---');
  подготовитьИгру(Игра, ЗЕРНО + 4);
  const игроки = МЕСТА.slice(0, 2);
  const [сдаётся, остаётся] = игроки;
  const п = Игра.раздать(сдаётся, { игроки: игроки, люди: игроки.slice(), хозяин: сдаётся });
  const ответ = Игра.сделатьХод(п, сдаётся, { действие: 'сдаться' });
  проверить(ответ.принято === true && ответ.событие === 'сдался', '(4) «сдаться» без номера раунда принято');
  проверить(п.завершена === true, '(4) партия.завершена');
  проверить(п.результат === остаётся, '(4) результат = оставшееся место');
  проверить(Array.isArray(п.проигравшие) && п.проигравшие.length === 1 && п.проигравшие[0] === сдаётся, '(4) проигравшие = сдавшийся');
  проверить(п.ничья === false, '(4) ничья: false');
  проверить(!!п.итог && Array.isArray(п.итог.места) && п.итог.места.length === 2 && п.итог.места[0].кто === остаётся,
    '(4) партия.итог записан, первое место — оставшийся');
  проверить(Игра.сделатьХод(п, остаётся, { действие: 'сдаться' }).принято === false, '(4) после конца ходов нет');

  /* Втроём сдача выбивает одного, партия идёт дальше (сдачаВыбывает). */
  const трое = МЕСТА.slice(0, 3);
  const п3 = Игра.раздать(трое[0], { игроки: трое, люди: [трое[0], трое[1]], хозяин: трое[0] });
  const сдача3 = Игра.сделатьХод(п3, трое[0], { действие: 'сдаться' });
  проверить(сдача3.принято === true && п3.завершена === false && Игра.вИгре(п3, трое[0]) === false && Игра.вИгре(п3, трое[1]) === true,
    '(4) втроём сдавшийся выбыл, партия идёт');
  const послеСдачи = Игра.сделатьХод(п3, трое[0], { действие: 'готово', раунд: п3.раунд });
  проверить(послеСдачи.принято === false && послеСдачи.причина === 'Вы уже не в игре', '(4) сдавшийся «Готово» не жмёт: «Вы уже не в игре»');
}

