/* =====================================================================
   Переворот доски к чёрным и кнопка «Другой соперник» — живой прогон.

     1) вдвоём: после хода белых доска повёрнута к чёрным, подписи полей
        переехали (цифра «1» сверху слева, буква «a» снизу справа),
        чёрная шашка по тапу поднимается; после хода чёрных — обратно;
     2) с роботом доска не поворачивается никогда;
     3) после партии «Другой соперник» убирает плашку, кнопки под доской
        нажимаются, новая партия начинается;
     4) плашка с тремя кнопками влезает в 320×568.
   ===================================================================== */

const { chromium } = require('./браузер-робот.js');
const ПОРТ = Number(process.argv[2]) || 8080;    // страничный сервер уже поднят
const АДРЕС = 'http://127.0.0.1:' + ПОРТ + '/шашки.html';
const ПАПКА = require('path').join(__dirname, 'скриншоты') + '/';

let провалов = 0;
function проверить(условие, слова) {
  console.log((условие ? '  ок   — ' : '  ПЛОХО— ') + слова);
  if (!условие) провалов++;
}

/** Снимок доски: повёрнута ли, где подписи, что над доской. */
async function осмотретьДоску(страница) {
  return страница.evaluate(() => {
    const доска = document.getElementById('доска');
    const клетки = Array.from(доска.children);
    const рамка = доска.getBoundingClientRect();
    const где = (узел) => {
      const у = узел.getBoundingClientRect();
      return { x: у.left - рамка.left, y: у.top - рамка.top };
    };
    const цифра1 = клетки.find((к) => к.querySelector('.метка-цифра') &&
      к.querySelector('.метка-цифра').textContent === '1');
    const букваA = клетки.find((к) => к.querySelector('.метка-буква') &&
      к.querySelector('.метка-буква').textContent === 'a');
    return {
      перевёрнута: доска.classList.contains('доска-шашек--перевёрнута'),
      клеток: клетки.length,
      первая: клетки[0].getAttribute('data-поле') || клетки[1].getAttribute('data-поле'),
      цифра1: где(цифра1),
      букваA: где(букваA),
      цифрСлева: клетки.filter((к) => к.querySelector('.метка-цифра')).length,
      буквСнизу: клетки.filter((к) => к.querySelector('.метка-буква')).length,
      строкаХода: document.getElementById('строка-хода').textContent,
      размер: Math.round(рамка.width)
    };
  });
}

async function сходитьСлучайно(страница) {
  await страница.evaluate(() => {
    const свои = Array.from(document.querySelectorAll('.фишка--может-ходить'));
    свои[Math.floor(Math.random() * свои.length)].parentElement.click();
  });
  await страница.waitForTimeout(30);
  await страница.evaluate(() => {
    const куда = Array.from(document.querySelectorAll('.поле--можно, .поле--можно-бой'));
    куда[Math.floor(Math.random() * куда.length)].click();
  });
  await страница.waitForTimeout(60);
}

/* Один тап: сперва подсвеченное поле (так доводится и цепочка боя),
   иначе — своя шашка. Посреди цепочки «шашек, которые могут ходить» нет
   вовсе, поэтому порядок именно такой. */
async function доигратьДоКонца(страница, предел) {
  for (let i = 0; i < предел; i++) {
    const кончено = await страница.evaluate(() =>
      document.getElementById('экран-итога').classList.contains('экран--виден'));
    if (кончено) return i;
    const что = await страница.evaluate(() => {
      const случайный = (список) => список[Math.floor(Math.random() * список.length)];
      const куда = Array.from(document.querySelectorAll('.поле--можно, .поле--можно-бой'));
      if (куда.length) { случайный(куда).click(); return 'ход'; }
      const свои = Array.from(document.querySelectorAll('.фишка--может-ходить'));
      if (свои.length) { случайный(свои).parentElement.click(); return 'поднял'; }
      return 'нечего';
    });
    await страница.waitForTimeout(что === 'нечего' ? 120 : 25);
  }
  return -1;
}

(async () => {
  const браузер = await chromium.launch();
  const окно = await браузер.newContext({ viewport: { width: 320, height: 568 }, deviceScaleFactor: 2 });
  const страница = await окно.newPage();
  const ошибки = [];
  страница.on('pageerror', (о) => ошибки.push('исключение: ' + о.message));
  страница.on('console', (с) => { if (с.type() === 'error') ошибки.push('консоль: ' + с.text()); });
  await страница.goto(АДРЕС);
  await страница.waitForTimeout(300);

  console.log('\n=== 1. Вдвоём: доска поворачивается к тому, кто ходит ===');
  let вид = await осмотретьДоску(страница);
  проверить(!вид.перевёрнута && вид.строкаХода === 'Ходят белые', 'старт: доска глазами белых, «' + вид.строкаХода + '»');
  проверить(вид.цифра1.y > вид.размер * 0.8 && вид.цифра1.x < вид.размер * 0.2,
    'цифра «1» внизу слева: x=' + Math.round(вид.цифра1.x) + ', y=' + Math.round(вид.цифра1.y));

  await сходитьСлучайно(страница);
  вид = await осмотретьДоску(страница);
  проверить(вид.перевёрнута, 'после хода белых доска повёрнута (класс доска-шашек--перевёрнута)');
  проверить(вид.строкаХода === 'Ходят чёрные', 'над доской «' + вид.строкаХода + '»');
  проверить(вид.клеток === 64, 'клеток по-прежнему 64');
  проверить(вид.цифрСлева === 8 && вид.буквСнизу === 8, 'подписей: цифр ' + вид.цифрСлева + ', букв ' + вид.буквСнизу);
  проверить(вид.цифра1.y < вид.размер * 0.2 && вид.цифра1.x < вид.размер * 0.2,
    'цифра «1» теперь сверху слева: x=' + Math.round(вид.цифра1.x) + ', y=' + Math.round(вид.цифра1.y));
  проверить(вид.букваA.y > вид.размер * 0.8 && вид.букваA.x > вид.размер * 0.8,
    'буква «a» теперь снизу справа: x=' + Math.round(вид.букваA.x) + ', y=' + Math.round(вид.букваA.y));
  await страница.screenshot({ path: ПАПКА + 'доска-перевёрнута-320.png' });

  // Чёрная шашка слушается после поворота
  const подсветка = await страница.evaluate(() => {
    const свои = document.querySelectorAll('.фишка--может-ходить');
    const чёрные = Array.from(свои).filter((ф) => ф.classList.contains('фишка--чёрная'));
    if (!чёрные.length) return { чёрных: 0, куда: 0 };
    чёрные[0].parentElement.click();
    return { чёрных: чёрные.length, куда: document.querySelectorAll('.поле--можно, .поле--можно-бой').length };
  });
  проверить(подсветка.чёрных > 0 && подсветка.куда > 0,
    'тап по чёрной шашке на повёрнутой доске подсветил ходы: шашек ' + подсветка.чёрных + ', полей ' + подсветка.куда);
  await страница.evaluate(() => {
    const куда = document.querySelector('.поле--можно, .поле--можно-бой');
    куда.click();
  });
  await страница.waitForTimeout(60);
  вид = await осмотретьДоску(страница);
  проверить(!вид.перевёрнута && вид.строкаХода === 'Ходят белые', 'после хода чёрных доска снова глазами белых');

  console.log('\n=== 2. С роботом доска не поворачивается ===');
  await страница.click('#уровень-лёгкий');
  await страница.click('#кнопка-с-ботом');
  await страница.waitForTimeout(150);
  await сходитьСлучайно(страница);
  вид = await осмотретьДоску(страница);
  проверить(!вид.перевёрнута, 'сразу после хода человека доска не повёрнута (ход робота)');
  await страница.waitForTimeout(900);
  вид = await осмотретьДоску(страница);
  проверить(!вид.перевёрнута && /Ваш ход/.test(вид.строкаХода), 'робот сходил, доска не повёрнута: «' + вид.строкаХода + '»');

  console.log('\n=== 3. «Другой соперник» после партии ===');
  await страница.click('#кнопка-вдвоём');
  await страница.waitForTimeout(100);
  const тапов = await доигратьДоКонца(страница, 900);
  проверить(тапов >= 0, 'партия вдвоём доиграна, ходов: ' + тапов);
  const плашка = await страница.evaluate(() => {
    const у = document.getElementById('экран-итога').getBoundingClientRect();
    const кнопки = ['кнопка-ещё', 'кнопка-рекорды-итог', 'кнопка-другой-соперник'].map((имя) => {
      const к = document.getElementById(имя).getBoundingClientRect();
      return имя + ' ' + Math.round(к.width) + '×' + Math.round(к.height) +
        (к.bottom <= window.innerHeight + 0.5 && к.right <= window.innerWidth + 0.5 ? '' : ' ВЫЛЕЗЛА');
    });
    return { высота: Math.round(у.height), низ: Math.round(у.bottom), кнопки: кнопки };
  });
  console.log('  плашка высотой ' + плашка.высота + ', низ на ' + плашка.низ + '; ' + плашка.кнопки.join(', '));
  проверить(плашка.низ <= 568 && !плашка.кнопки.some((к) => /ВЫЛЕЗЛА/.test(к)), 'плашка с тремя кнопками влезла в 320×568');
  await страница.screenshot({ path: ПАПКА + 'плашка-три-кнопки-320.png' });

  await страница.click('#кнопка-другой-соперник');
  await страница.waitForTimeout(100);
  const после = await страница.evaluate(() => ({
    плашкаВидна: document.getElementById('экран-итога').classList.contains('экран--виден'),
    строкаХода: document.getElementById('строка-хода').textContent
  }));
  проверить(!после.плашкаВидна, 'плашка убралась');
  проверить(/выберите, с кем играть/.test(после.строкаХода), 'над доской объяснение: «' + после.строкаХода + '»');

  await страница.click('#уровень-сложный');            // раньше эту кнопку перехватывала плашка
  await страница.click('#кнопка-с-ботом');
  await страница.waitForTimeout(150);
  const новая = await страница.evaluate(() => ({
    строкаХода: document.getElementById('строка-хода').textContent,
    шашек: document.querySelectorAll('.фишка').length,
    сложныйВыбран: document.getElementById('уровень-сложный').classList.contains('кнопка--активная')
  }));
  проверить(новая.шашек === 24 && /Ваш ход/.test(новая.строкаХода) && новая.сложныйВыбран,
    'выбор уровня и «Играть с ботом» сработали без плашки: «' + новая.строкаХода + '», шашек ' + новая.шашек);

  проверить(ошибки.length === 0, 'красных ошибок нет' + (ошибки.length ? ': ' + ошибки.join(' | ') : ''));
  await браузер.close();
  console.log('\n' + (провалов === 0 ? 'ВСЁ ЗЕЛЁНОЕ' : 'ПРОВАЛОВ: ' + провалов));
  process.exit(провалов === 0 ? 0 : 1);
})().catch((о) => { console.error('проверка сломалась:', о); process.exit(2); });
