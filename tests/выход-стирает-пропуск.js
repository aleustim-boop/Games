const path = require('path');
const http = require('http');
const net = require('net');
const { spawn } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const ПОРТ = 8863;
const ХОСТ = '127.0.0.1';

let проверок = 0;
let провалов = 0;
function проверить(условие, слова) {
  проверок++;
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}
const спать = (мс) => new Promise((готово) => setTimeout(готово, мс));

/** Порт свободен? Пробуем настоящее TCP-соединение с коротким сроком. */
function портСвободен(порт) {
  return new Promise(function (готово) {
    const сокет = net.createConnection({ host: ХОСТ, port: порт, timeout: 800 });
    сокет.once('connect', function () { сокет.destroy(); готово(false); });   // ответил — занят
    сокет.once('timeout', function () { сокет.destroy(); готово(true); });    // никто не откликнулся — свободен
    сокет.once('error', function () { готово(true); });                      // отказали в соединении — свободен
  });
}

/** Поднять node-процесс и дождаться в его stdout приметы готовности (тот же приём, что tests/сдаться-в-шашках-по-сети.js). */
function поднять(файл, доводы, приметаГотовности) {
  return new Promise(function (готово, беда) {
    const дитя = spawn('node', [файл].concat(доводы));
    let вывод = '';
    const срок = setTimeout(function () {
      дитя.kill();
      беда(new Error('процесс ' + файл + ' не поднялся за 15 секунд, вывод: ' + вывод));
    }, 15000);
    дитя.stdout.on('data', function (кусок) {
      вывод += кусок;
      if (приметаГотовности.test(вывод)) { clearTimeout(срок); готово(дитя); }
    });
    дитя.stderr.on('data', function (кусок) { вывод += кусок; });
    дитя.on('error', беда);
    дитя.on('exit', function (код) {
      if (код !== null && код !== 0) беда(new Error('процесс ' + файл + ' упал с кодом ' + код + ': ' + вывод));
    });
  });
}

/** POST-запрос к серверу комнат — отдаёт и код ответа, и разобранное тело. */
function запрос(путь, тело) {
  return new Promise(function (готово, беда) {
    const текст = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const обращение = http.request({
      host: ХОСТ, port: ПОРТ, method: 'POST', path: encodeURI('/' + путь),
      headers: { 'Content-Type': 'application/json', 'Content-Length': текст.length }
    }, function (ответ) {
      let куски = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (ч) { куски += ч; });
      ответ.on('end', function () {
        let данные = {};
        try { данные = JSON.parse(куски); } catch (сбой) { данные = { сыройОтвет: куски }; }
        готово({ номер: ответ.statusCode, данные: данные });
      });
    });
    обращение.setTimeout(10000, function () { обращение.destroy(new Error('сервер не ответил на /' + путь)); });
    обращение.on('error', беда);
    обращение.end(текст);
  });
}

/** Найти в «застолом» место с данным номером. */
function найтиМесто(застолом, номер) {
  return (застолом || []).find(function (м) { return м.номер === номер; }) || null;
}

/** Довести партию дурака до состояния «у места №3 есть хоть одна карта в руке» — начать он мог не сразу. */
async function дождатьсяРукиТретьего(код, пропуск3, пропытокМакс) {
  for (let i = 0; i < пропытокМакс; i++) {
    const о = await запрос('состояние', { код: код, пропуск: пропуск3 });
    if (о.номер === 200 && о.данные.состояние && Array.isArray(о.данные.состояние.мояРука) && о.данные.состояние.мояРука.length > 0) {
      return о;
    }
    await спать(150);
  }
  return запрос('состояние', { код: код, пропуск: пропуск3 });
}

