'use strict';

/* Проверка сводки по приглашениям (server/приглашения.js, сводка(дней)).
   Чистый node, без браузера и без сети. Данные — во временной папке:
   настоящая server/данные не трогается (путь уводится через ДАННЫЕ_ИГРЫ).

   Запуск:            node tests/учёт-приглашений-сводка.js
   Ломающий запуск:   node tests/учёт-приглашений-сводка.js <путь к КОПИИ приглашения.js>
   Копия лежит рядом со своей копией папка-данных.js во временной папке;
   на испорченной копии проверка обязана покраснеть (код выхода 1). */

const fs = require('fs');
const os = require('os');
const path = require('path');

const папкаДанных = fs.mkdtempSync(path.join(os.tmpdir(), 'сводка-приглашений-'));
process.env.ДАННЫЕ_ИГРЫ = папкаДанных;
process.env.GAMES_DATA = папкаДанных;

const путьМодуля = process.argv[2]
  ? path.resolve(process.argv[2])
  : path.join(__dirname, '..', 'server', 'приглашения.js');
const приглашения = require(путьМодуля);

let провалов = 0;
let всего = 0;
function проверить(что, правда, подробность) {
  всего++;
  if (правда) {
    console.log('ок    ' + что);
  } else {
    провалов++;
    console.log('ПРОВАЛ ' + что + (подробность ? ' — ' + подробность : ''));
  }
}
function равно(что, нашли, ждали) {
  const а = JSON.stringify(нашли);
  const б = JSON.stringify(ждали);
  проверить(что, а === б, 'нашли ' + а + ', ждали ' + б);
}

const ДЕНЬ = 24 * 60 * 60 * 1000;
const ПРИГЛАСИВШИЙ_1 = 7100001;
const ДРУГ_1 = 7100002;
const ПРИГЛАСИВШИЙ_2 = 7100003;
const ДРУГ_2 = 7100004;
const ХОЛОСТОЙ = 7100005;
const СТАРЫЙ = 7100006;
const ТЕСТОВЫЙ = 7100009;

/* Тестовый человек — как в бою: файл тестовые.json в папке данных. */
fs.writeFileSync(path.join(папкаДанных, 'тестовые.json'), JSON.stringify([ТЕСТОВЫЙ]));

/* Старое приглашение (30 дней назад, комната от прошлого запуска): попадёт
   в «за 60 дней» и в «сгорело», но не в «за 7 дней». */
const давно = Date.now() - 30 * ДЕНЬ;
fs.writeFileSync(path.join(папкаДанных, 'приглашения.json'), JSON.stringify({
  записи: {
    old00001: {
      создано: давно, кто: СТАРЫЙ, игра: 'шахматы', код: 'OLD1', комнатаСоздана: давно,
      события: [
        { что: 'создано', когда: давно },
        { что: 'окноОткрыто', когда: давно, соСловКлиента: true },
        { что: 'отправлено', когда: давно, соСловКлиента: true }
      ]
    }
  }
}));

/* Приглашение 1: окно → отправлено → друг сел → старт → итог (доиграна). */
const номер1 = приглашения.создать(ПРИГЛАСИВШИЙ_1, 'дурак', 'ABCD', Date.now());
приглашения.отметитьСоСловКлиента(номер1, ПРИГЛАСИВШИЙ_1, 'окноОткрыто');
приглашения.отметитьСоСловКлиента(номер1, ПРИГЛАСИВШИЙ_1, 'отправлено');
приглашения.отметитьСервером(номер1, 'вход', { место: 'b', кто: ДРУГ_1 });
приглашения.отметитьСервером(номер1, 'старт', { место: 'b', кто: ДРУГ_1 });
приглашения.отметитьСервером(номер1, 'итог', { место: 'b', кто: ДРУГ_1, доиграна: true });

/* Приглашение 2: окно → скопировано → друг упёрся в «идёт». */
const номер2 = приглашения.создать(ПРИГЛАСИВШИЙ_2, 'шашки', 'WXYZ', Date.now());
приглашения.отметитьСоСловКлиента(номер2, ПРИГЛАСИВШИЙ_2, 'окноОткрыто');
приглашения.отметитьСоСловКлиента(номер2, ПРИГЛАСИВШИЙ_2, 'скопировано');
const отказПринят = приглашения.отметитьОтказВхода(номер2, 'WXYZ', ДРУГ_2, 'идёт');

/* Приглашение 3: тестового человека — считаться не должно. */
const номер3 = приглашения.создать(ТЕСТОВЫЙ, 'дурак', 'TEST', Date.now());
приглашения.отметитьСоСловКлиента(номер3, ТЕСТОВЫЙ, 'окноОткрыто');
приглашения.отметитьСоСловКлиента(номер3, ТЕСТОВЫЙ, 'отправлено');
приглашения.отметитьСервером(номер3, 'вход', { место: 'b', кто: ДРУГ_1 });

/* Холостая запись: номер выдан, человек ничего не нажал. */
const номер4 = приглашения.создать(ХОЛОСТОЙ, 'дурак', 'IDLE', Date.now());

проверить('номера выданы', [номер1, номер2, номер3, номер4].every(function (н) { return /^[a-z0-9]{8}$/.test(н); }));
проверить('отказ входа записан', отказПринят === true);
проверить('запись тестового помечена тест', (приглашения.запись(номер3) || {}).тест === true);

const неделя = приглашения.сводка(7);
равно('за 7 дней: приглашений — 2 (тестовое и холостое не считаются)', неделя.приглашений, 2);
равно('за 7 дней: окно открыто — 2', неделя.окноОткрыто, 2);
равно('за 7 дней: отправлено — 1', неделя.отправлено, 1);
равно('за 7 дней: скопировано — 1', неделя.скопировано, 1);
равно('за 7 дней: друг сел — 1', неделя.другСел, 1);
равно('за 7 дней: партия начата — 1', неделя.партияНачата, 1);
равно('за 7 дней: доиграли — 1', неделя.доиграли, 1);
равно('за 7 дней: отказы', неделя.отказы, { 'идёт': 1, 'заполнена': 0, 'закрыта': 0, 'нет': 0 });
равно('за 7 дней: сгорело — 0', неделя.сгорело, 0);
равно('за 7 дней: по играм — дурак и шашки',
  Object.keys(неделя.поИграм).sort(), ['дурак', 'шашки']);
равно('за 7 дней: дурак — одно приглашение, доиграли', [неделя.поИграм['дурак'] && неделя.поИграм['дурак'].приглашений,
  неделя.поИграм['дурак'] && неделя.поИграм['дурак'].доиграли], [1, 1]);
равно('за 7 дней: шашки — одно приглашение, друг не сел', [неделя.поИграм['шашки'] && неделя.поИграм['шашки'].приглашений,
  неделя.поИграм['шашки'] && неделя.поИграм['шашки'].другСел], [1, 0]);

const шестьдесят = приглашения.сводка(60);
равно('за 60 дней: приглашений — 3 (старое вошло)', шестьдесят.приглашений, 3);
равно('за 60 дней: отправлено — 2', шестьдесят.отправлено, 2);
равно('за 60 дней: сгорело — 1 (комната прошлого запуска)', шестьдесят.сгорело, 1);
проверить('за 60 дней: шахматы в разбивке', Object.keys(шестьдесят.поИграм).indexOf('шахматы') !== -1);
равно('без аргумента — за всё хранимое', приглашения.сводка().приглашений, 3);

/* В сводке нет ни номеров игроков, ни номеров приглашений, ни кодов столов. */
const текст = JSON.stringify(шестьдесят);
const чужоеВТексте = [ПРИГЛАСИВШИЙ_1, ДРУГ_1, ПРИГЛАСИВШИЙ_2, ДРУГ_2, ХОЛОСТОЙ, СТАРЫЙ, ТЕСТОВЫЙ,
  номер1, номер2, номер3, номер4, 'old00001', 'ABCD', 'WXYZ', 'OLD1']
  .filter(function (штука) { return текст.indexOf(String(штука)) !== -1; });
равно('в сводке нет номеров игроков, приглашений и кодов столов', чужоеВТексте, []);
проверить('в сводке нет длинных чисел', !/\d{6,}/.test(текст), текст);

/* Диск за собой не оставляем: папка временная, в бою её нет. */
fs.rmSync(папкаДанных, { recursive: true, force: true });

console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
if (провалов > 0) {
  process.exit(1);
}
console.log('\nЗЕЛЕНО: сводка по приглашениям сходится');
