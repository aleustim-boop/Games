/* ---------------------------------------------------------------------
   А) Разметка
   --------------------------------------------------------------------- */
function проверитьРазметку() {
  надо(ID_КАРТОЧКИ !== '', 'А0) в игры/дурак/game.js есть КАРТОЧКА_ТУРНИРА', 'нет строки const КАРТОЧКА_ТУРНИРА');
  const начало = ТЕКСТ_INDEX.indexOf('id="экран-лобби"');
  const конец = начало === -1 ? -1 : ТЕКСТ_INDEX.indexOf('</section>', начало);
  надо(начало !== -1 && конец !== -1, 'А1) в index.html есть секция #экран-лобби');
  const лобби = начало !== -1 && конец !== -1 ? ТЕКСТ_INDEX.slice(начало, конец) : '';

  /* Ищем открывающий тег кнопки с нужным id. Ноль — провал. */
  const теги = лобби.match(/<button\b[^>]*>/g) || [];
  const нашей = теги.filter((т) => ID_КАРТОЧКИ && т.indexOf('id="' + ID_КАРТОЧКИ + '"') !== -1);
  надо(нашей.length === 1, 'А2) в лобби ровно одна кнопка с id «' + ID_КАРТОЧКИ + '»', 'найдено: ' + нашей.length);
  const тег = нашей[0] || '';
  const классы = ((/class="([^"]*)"/.exec(тег) || [])[1] || '').split(/\s+/);
  надо(классы.indexOf('карточка-входа') !== -1 && классы.indexOf('карточка-входа--турнир') !== -1,
    'А3) у карточки классы «карточка-входа» и «карточка-входа--турнир»', 'классы: ' + классы.join(' '));
  надо(классы.indexOf('скрыт') !== -1,
    'А4) до загрузки экрана турнира карточка спрятана (класс «скрыт»)', 'классы: ' + классы.join(' '));

  const гдеРаздача = лобби.indexOf('id="карточка-раздачи-дня"');
  const гдеТурнир = ID_КАРТОЧКИ ? лобби.indexOf('id="' + ID_КАРТОЧКИ + '"') : -1;
  const гдеДрузья = лобби.indexOf('id="лобби-друзья"');
  надо(гдеРаздача !== -1 && гдеТурнир > гдеРаздача && (гдеДрузья === -1 || гдеТурнир < гдеДрузья),
    'А5) карточка стоит сразу после «Раздачи дня»',
    'раздача ' + гдеРаздача + ', турнир ' + гдеТурнир + ', друзья ' + гдеДрузья);
  /* Между «Раздачей дня» и турниром других кнопок нет: в отрезке от id
     раздачи до id турнира ровно один «<button» — открывающий тег турнира. */
  const между = гдеРаздача !== -1 && гдеТурнир > гдеРаздача ? лобби.slice(гдеРаздача, гдеТурнир) : '';
  надо(гдеТурнир > гдеРаздача && (между.match(/<button\b/g) || []).length === 1,
    'А6) между «Раздачей дня» и турниром других кнопок нет');

  const тело = гдеТурнир !== -1 ? лобби.slice(гдеТурнир, лобби.indexOf('</button>', гдеТурнир)) : '';
  надо(тело.indexOf('Турнир дня') !== -1, 'А7) заголовок карточки «Турнир дня»');
  надо(тело.indexOf('Каждый день в 20:00') !== -1 && !/МСК/.test(тело), 'А8) подпись «Каждый день в 20:00» без пояса');
  надо(тело.indexOf('карточка-входа__значок') !== -1 && тело.indexOf('карточка-входа__стрелка') !== -1,
    'А9) каркас карточки как у соседей: значок и стрелка');
}

