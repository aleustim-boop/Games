'use strict';

/* =====================================================================
   СТОРОЖ ПОЛЕЙ ДЛЯ НАРД — проверка ветки «нарды» в общем сторожеe
   (tests/сторож-полей.js).

   ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. tests/сторож-полей.js — общая библиотека сразу
   для трёх сетевых прогонов, и лезть с проверкой одной игры в чужие
   автопрогоны неправильно: они про партию целиком, а не про сторожа.
   До этой правки сторож умел различать только шашки: всё, что не шашки,
   он считал дураком и требовал в ответе «картУСоперника», «вКолоде»,
   «вОтбое» числами. Разработчик нард наткнулся на это сам (три ложных
   провала) и написал свой маленький осмотр прямо в
   tests/нарды-сервер-правила.js — а общий файл не тронул: не его файл.
   Эта проверка — ответ на его находку: у сторожа появилась настоящая
   ветка «нарды», и вот доказательство, что она работает.

   ЧТО ПРОВЕРЯЕМ. Берём НАСТОЯЩИЙ вид игрока — через server/игры/нарды.js
   (раздать → видДляИгрока), как это делает tests/нарды-сервер-правила.js,
   без сети и без сервера комнат:

     1) честный вид (после раздачи и одного сыгранного хода) — сторож
        молчит целиком, ни одного провала;
     2) в честный вид подмешали «картУСоперника» — сторож обязан
        поймать (ноль пойманного здесь — сам по себе провал проверки);
     3) в честный вид подмешали внутреннее имя места сервера («ключ»
        того, кто сидит за столом, — сервер использует его как ключ
        карты места, см. server/игры/нарды.js) — сторож обязан поймать;
     4) из честного вида убрали «доска» — сторож обязан поймать.

   ЛОМАЮЩИЙ ЗАПУСК (проверка обязана уметь краснеть):
       node tests/сторож-полей-нарды.js --сломать

   Копирует tests/сторож-полей.js во временную папку и в КОПИИ отключает
   ветку «нарды» (нарды снова попадают в «иначе» — туда же, где дурак).
   На честном виде нард копия обязана споткнуться о «картУСоперника
   пришли не числом» — то есть провалиться там, где обычный запуск
   молчит. Не споткнулась — проверка смотрит не туда, и это провал уже
   этого файла. Строка для порчи не нашлась — считаем, что ломать нечего,
   и выходим кодом 2 отдельно от обычных провалов.
   Файл проекта при этом не трогается ни на секунду.

   Запуск:
       node tests/сторож-полей-нарды.js
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ПУТЬ_СТОРОЖА = path.join(КОРЕНЬ, 'tests', 'сторож-полей.js');
const ПУТЬ_ИГРЫ = path.join(КОРЕНЬ, 'server', 'игры', 'нарды.js');
const ПУТЬ_ПРАВИЛ = path.join(КОРЕНЬ, 'js', 'нарды-правила.js');

const БЕЛЫЕ_МЕСТО = 'человек';   // те же внутренние имена мест, что у комнаты
const ЧЁРНЫЕ_МЕСТО = 'бот';

/* --- счёт проверок --- */
let всегоПроверок = 0;
let провалов = 0;

function проверить(условие, слова) {
  всегоПроверок++;
  if (условие) {
    console.log('  ок    — ' + слова);
  } else {
    провалов++;
    console.log('  ПЛОХО — ' + слова);
  }
}

/* =====================================================================
   ЧЕСТНЫЙ ВИД: раздача через настоящий модуль сервера
   ===================================================================== */

/**
 * Раздать стол и сыграть один ход, чтобы «бросок», «кубикиОсталось»
 * и «последнийХод» в виде оказались не пустыми, а настоящими —
 * пустое состояние сторож бы пропустил молча (undefined тоже законен),
 * и проверка формы полей осталась бы непроверенной.
 * Возвращает вид ЖДУЩЕГО игрока — у него как раз и заполнен
 * «последнийХод» чужим ходом, это самое насыщенное состояние.
 */
function честныйВид(Игра, Правила) {
  const партия = Игра.раздать(БЕЛЫЕ_МЕСТО, {
    игроки: [БЕЛЫЕ_МЕСТО, ЧЁРНЫЕ_МЕСТО],
    вариантНард: 'короткие'
  });

  const бросили = Игра.сделатьХод(партия, БЕЛЫЕ_МЕСТО, { действие: 'бросить' });
  if (!бросили.принято) throw new Error('честныйВид: бросок не принят — ' + бросили.причина);

  const ходы = Правила.возможныеХоды(партия.доска);
  const шаги = ходы.length ? ходы[0].шаги.map(function (ш) {
    return { откуда: ш.откуда, куда: ш.куда, кубик: ш.кубик };
  }) : [];
  const сходили = Игра.сделатьХод(партия, БЕЛЫЕ_МЕСТО, { действие: 'ход', шаги: шаги });
  if (!сходили.принято) throw new Error('честныйВид: ход не принят — ' + сходили.причина);

  // Компанию (список мест за столом) добавляем сами — комната делает так же
  // до самой раздачи и после неё, когда стол показывают в прихожей.
  const места = [
    { ключ: БЕЛЫЕ_МЕСТО, номер: 1, имя: 'Аня', хозяин: true, наСвязи: true },
    { ключ: ЧЁРНЫЕ_МЕСТО, номер: 2, имя: 'Витя', хозяин: false, наСвязи: true }
  ];
  return Игра.видДляИгрока(партия, ЧЁРНЫЕ_МЕСТО, {
    места: места, мест: 2, мойНомер: 2, яХозяин: false, можноНачать: true,
    этап: 'идёт'
  });
}

/** Глубокая копия вида — чтобы порча одного сценария не задела другой. */
function копия(вид) {
  return JSON.parse(JSON.stringify(вид));
}

/** Прогнать сторожа по одному виду и посчитать, сколько раз он сказал «плохо». */
function осмотретьСторожем(создатьСторожа, вид, откуда) {
  const беды = [];
  const сторож = создатьСторожа(function (условие, слова) {
    if (!условие) беды.push(слова);
  });
  сторож.осмотреть(вид, откуда);
  return беды;
}

/* =====================================================================
   ЧЕТЫРЕ СЦЕНАРИЯ
   ===================================================================== */

function прогнатьСценарии(создатьСторожа, честный) {
  console.log('\n--- 1. Честный вид нард — сторож молчит ---');
  const бедыЧестного = осмотретьСторожем(создатьСторожа, честный, 'честный вид');
  проверить(бедыЧестного.length === 0,
    'на честном виде провалов нет (получено: ' + бедыЧестного.length + ')' +
    (бедыЧестного.length ? ' — ' + бедыЧестного.join('; ') : ''));

  console.log('\n--- 2. Подмешали «картУСоперника» — сторож обязан поймать ---');
  const сКартами = копия(честный);
  сКартами.картУСоперника = 5;
  const бедыКарт = осмотретьСторожем(создатьСторожа, сКартами, 'вид с картУСоперника');
  проверить(бедыКарт.length > 0,
    'сторож поймал подмешанные карты соперника (поймано: ' + бедыКарт.length + ')');

  console.log('\n--- 3. Подмешали внутреннее имя места сервера («ключ») — сторож обязан поймать ---');
  const сКлючом = копия(честный);
  if (!Array.isArray(сКлючом.застолом) || !сКлючом.застолом.length) {
    throw new Error('в честном виде нет «застолом» — сценарию №3 нечего портить');
  }
  сКлючом.застолом[0].ключ = БЕЛЫЕ_МЕСТО;
  const бедыКлюча = осмотретьСторожем(создатьСторожа, сКлючом, 'вид с внутренним ключом места');
  проверить(бедыКлюча.length > 0,
    'сторож поймал внутреннее имя места (поймано: ' + бедыКлюча.length + ')');

  console.log('\n--- 4. Убрали «доска» — сторож обязан поймать ---');
  const безДоски = копия(честный);
  delete безДоски.доска;
  const бедыБезДоски = осмотретьСторожем(создатьСторожа, безДоски, 'вид без доски');
  проверить(бедыБезДоски.length > 0,
    'сторож поймал пропавшую доску (поймано: ' + бедыБезДоски.length + ')');

  return бедыЧестного;
}

/* =====================================================================
   ЛИШНЯЯ СТРАХОВКА: соседей моя правка не потревожила
   ===================================================================== */

/** Маленький честный вид шашек — вручную, без сети: только форма ответа. */
function честныйВидШашек() {
  return {
    игра: 'шашки',
    этап: 'идёт',
    доска: ['ЧЧЧЧ....', '.ЧЧЧЧ...', '........', '........',
      '........', '........', '...ббббб', '....бббб'],
    чейХод: 'белые',
    мойЦвет: 'белые',
    естьБой: false,
    завершена: false
  };
}

function проверитьЧтоШашкиНеЗадеты(создатьСторожа) {
  console.log('\n--- Страховка: честный вид шашек по-прежнему проходит молча ---');
  const беды = осмотретьСторожем(создатьСторожа, честныйВидШашек(), 'честный вид шашек');
  проверить(беды.length === 0,
    'ветка шашек не пострадала от правки нард (провалов: ' + беды.length + ')' +
    (беды.length ? ' — ' + беды.join('; ') : ''));
}

/* =====================================================================
   ОБЫЧНЫЙ ЗАПУСК
   ===================================================================== */

function обычныйЗапуск() {
  console.log('=== Сторож полей: ветка «нарды» ===');
  const { создатьСторожа } = require(ПУТЬ_СТОРОЖА);
  const Игра = require(ПУТЬ_ИГРЫ);
  const Правила = require(ПУТЬ_ПРАВИЛ);

  const честный = честныйВид(Игра, Правила);
  прогнатьСценарии(создатьСторожа, честный);
  проверитьЧтоШашкиНеЗадеты(создатьСторожа);

  console.log('\nИтого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
  if (всегоПроверок === 0) {
    console.log('ПЛОХО: не сделано ни одной проверки — она смотрит не туда');
    process.exitCode = 1;
    return;
  }
  if (провалов > 0) {
    process.exitCode = 1;
  } else {
    console.log('Сторож различает нарды: честному виду верит, подмешанное ловит.');
  }
}

/* =====================================================================
   ЛОМАЮЩИЙ ЗАПУСК: портим КОПИЮ сторожа во временной папке —
   отключаем ветку «нарды», нарды снова считаются дураком.
   Файл проекта не трогаем и не откатываем.
   ===================================================================== */

function ломающийЗапуск() {
  console.log('=== Ломающий запуск: в копии сторожа ветка «нарды» отключена ===\n');

  const исходник = fs.readFileSync(ПУТЬ_СТОРОЖА, 'utf8');

  const замены = [
    [
      "const свои = игра === 'шашки' ? ПОЛЯ_ШАШЕК\n    : (игра === 'нарды' ? ПОЛЯ_НАРД : ПОЛЯ_ДУРАКА);",
      "const свои = игра === 'шашки' ? ПОЛЯ_ШАШЕК : ПОЛЯ_ДУРАКА;"
    ],
    [
      "} else if (состояние.игра === 'нарды') {",
      "} else if (false && состояние.игра === 'нарды') {"
    ]
  ];

  let порченый = исходник;
  let замененоВсего = 0;
  for (const [было, стало] of замены) {
    if (порченый.indexOf(было) === -1) {
      console.log('ПЛОХО: в сторожеe не нашлась строка для порчи — ломать нечего.');
      console.log('       Искали: ' + было);
      process.exitCode = 2;
      return;
    }
    const было_ли = порченый;
    порченый = порченый.split(было).join(стало);
    if (порченый !== было_ли) замененоВсего++;
  }

  if (замененоВсего === 0) {
    console.log('ПЛОХО: ни одной замены не вышло — ломать нечего.');
    process.exitCode = 2;
    return;
  }

  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'сторож-нарды-'));
  const копияСторожа = path.join(папка, 'сторож-полей.js');
  try {
    fs.writeFileSync(копияСторожа, порченый, 'utf8');
    console.log('  порченая копия: ' + копияСторожа + '\n');

    const { создатьСторожа } = require(копияСторожа);
    const Игра = require(ПУТЬ_ИГРЫ);
    const Правила = require(ПУТЬ_ПРАВИЛ);
    const честный = честныйВид(Игра, Правила);

    const беды = осмотретьСторожем(создатьСторожа, честный, 'честный вид, порченый сторож');
    console.log('  на честном виде порченый сторож нашёл провалов: ' + беды.length);
    беды.forEach(function (слова) { console.log('   ' + слова); });

    const проКарты = беды.filter(function (слова) {
      return слова.indexOf('картУСоперника') !== -1 || слова.indexOf('карты соперника') !== -1;
    });
    if (проКарты.length > 0) {
      console.log('\nЛомающий запуск покраснел, как и должен: отключённая ветка «нарды» ' +
        'заставляет честную партию требовать карты соперника числом.');
    } else {
      console.log('\nПЛОХО: порченый сторож смолчал на честном виде нард — проверка смотрит не туда');
      process.exitCode = 1;
    }
  } finally {
    try { delete require.cache[require.resolve(копияСторожа)]; } catch (е) { /* не грузился — и ладно */ }
    try { fs.unlinkSync(копияСторожа); } catch (е) { /* уже нет — и ладно */ }
    try { fs.rmdirSync(папка); } catch (е) { /* уже нет — и ладно */ }
  }
}

if (process.argv.indexOf('--сломать') !== -1) {
  ломающийЗапуск();
} else {
  обычныйЗапуск();
}
