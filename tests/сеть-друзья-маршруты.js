(async function () {
  console.log('=== Друзья: пять дверей /друзья-* ===');
  console.log('свой сервер на http://' + ХОЗЯИН_АДРЕС + ':' + ПОРТ + ' (боевой 8790 не трогаем)');
  console.log('Telegram поддельный, токен выдуманный, данные в ' + process.env.ДАННЫЕ_ИГРЫ + '\n');

  сервера.оснасткаДляПроверки(ТОКЕН_ДЛЯ_ПРОБЫ, поддельныйTelegram);

  const сервер = сервера.создатьСервер();
  await new Promise(function (готово, беда) {
    сервер.once('error', беда);
    сервер.listen(ПОРТ, ХОЗЯИН_АДРЕС, готово);
  });

  let сбой = null;
  try {
    await проверитьВсё();
  } catch (беда) {
    сбой = беда;
  } finally {
    /* Гасим сервер при любом исходе — упала проверка или нет. Отдельного
       процесса и PID здесь нет (см. заголовок файла, почему): сервер
       живёт в этом же процессе, и гасим ровно ту его часть, которую
       сами подняли — слушающий сокет. */
    сервер.close();
    сервера.оснасткаДляПроверки();     // возвращаем настоящий токен и настоящую трубу
  }

  console.log('\n----------------------------------------');
  if (сбой) {
    console.log('ПРОВЕРКА ОБОРВАЛАСЬ: ' + сбой.message);
    console.log(сбой.stack);
  }
  for (const беда of провалы) console.log('  - ' + беда);
  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалы.length);
  console.log('\nЧего этой проверкой не увидеть: как двери ведут себя с НАСТОЯЩИМ Telegram ' +
              'и настоящим токеном — для этого нужен токен бота, а проверка его не трогает. ' +
              'Предел числа друзей (300 на человека, см. server/друзья.js) здесь тоже не проверить — ' +
              'заводить триста связей ради одной сверки слишком дорого.');

  process.exit(сбой || провалы.length > 0 ? 1 : 0);
})();
