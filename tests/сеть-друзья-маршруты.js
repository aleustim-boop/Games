function поддельныйTelegram() {
  return { ok: false, error_code: 400, description: 'Bad Request' };
}

/* ---------------------------------------------------------------------
   Подпись Telegram — по тому же правилу, что у сервера
   --------------------------------------------------------------------- */

function подписать(поля, токен) {
  const строки = Object.keys(поля)
    .filter(function (к) { return к !== 'hash'; })
    .map(function (к) { return к + '=' + поля[к]; })
    .sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(токен).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}

/** initData так, как её присылает настоящая страница Telegram. */
function подписьИгрока(номер, имя) {
  const поля = {
    query_id: 'AAF' + номер,
    user: JSON.stringify({ id: номер, first_name: имя, username: 'igrok' + номер }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  const сподписью = Object.assign({}, поля, { hash: подписать(поля, ТОКЕН_ДЛЯ_ПРОБЫ) });
  return Object.keys(сподписью)
    .map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(сподписью[к]); })
    .join('&');
}

/* ---------------------------------------------------------------------
   Разговор с дверью
   --------------------------------------------------------------------- */

function спросить(путь, тело) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН_АДРЕС, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (сбой) { разобрано = null; }
        готово({ код: ответ.statusCode, тело: разобрано, текст: текст });
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

/** Ответ двери c учётом --сломать: любой ответ становится «ок:true» с пустыми списками. */
function испортить(данные) {
  if (!ЛОМАТЬ) return данные || {};
  return {
    узналиВас: true, ок: true, причина: '', статус: 'друзья',
    друзья: [], входящие: []
  };
}

/** Ключ, каким его называет проверка после --сломать: похож на голый номер. */
function испортитьКлюч(ключ) {
  return ЛОМАТЬ ? '202' : ключ;
}

/** Короткий помощник: подписанный запрос от имени игрока к одной из дверей друзей. */
function дверь(путь, кто, имя, довесок) {
  const тело = Object.assign({ initData: подписьИгрока(кто, имя) }, довесок || {});
  return спросить(путь, тело).then(function (ответ) { return испортить(ответ.тело); });
}

/** Найти запись знакомого/друга/входящего в списке по имени. */
function найтиПоИмени(список, имя) {
  return (список || []).find(function (запись) { return запись.имя === имя; });
}

/* ---------------------------------------------------------------------
   Сами проверки
   --------------------------------------------------------------------- */

async function проверитьВсё() {
  /* Кто с кем играл — заводим напрямую, без партии (см. заголовок файла). */
  знакомые.забытьВсё();
  друзья.забытьВсё();
  знакомые.запомнитьЗастолье([{ номер: АНЯ, имя: 'Аня' }, { номер: БОРЯ, имя: 'Боря' }], 'дурак');
  знакомые.запомнитьЗастолье([{ номер: ВИТЯ, имя: 'Витя' }, { номер: БОРЯ, имя: 'Боря' }], 'дурак');

  // --- 1. Знакомые заведены, но НЕ друзья: список у А пуст
  console.log('1. У А пока нет ни друзей, ни входящих заявок');
  const списокАдоЗова = испортить((await спросить('/друзья-список', { initData: подписьИгрока(АНЯ, 'Аня') })).тело);
  проверить(списокАдоЗова.узналиВас === true, 'дверь /друзья-список не узнала игрока по верной подписи');
  проверить(Array.isArray(списокАдоЗова.друзья) && списокАдоЗова.друзья.length === 0,
    'у А до всякого зова уже что-то стоит в друзьях');
  проверить(Array.isArray(списокАдоЗова.входящие) && списокАдоЗова.входящие.length === 0,
    'у А до всякого зова уже что-то стоит во входящих');

  // --- 2. Достаём ключ Бори из /знакомые (тем же приёмом, что зов знакомого)
  console.log('2. Ключ Бори берём из /знакомые Ани');
  const знакомыеАни = (await спросить('/знакомые', { initData: подписьИгрока(АНЯ, 'Аня') })).тело;
  const ключБориУАни = ((знакомыеАни && знакомыеАни.знакомые) || [])
    .find(function (з) { return з.имя === 'Боря'; });
  проверить(Boolean(ключБориУАни), 'Боря не нашёлся в списке знакомых Ани — дальше звать нечем');
  const КЛЮЧ_БОРИ_У_АНИ = (ключБориУАни || {}).ключ || '';

  // --- 3. А зовёт Б в друзья
  console.log('3. А зовёт Б в друзья');
  const зов = await дверь('/друзья-позвать', АНЯ, 'Аня', { ключ: испортитьКлюч(КЛЮЧ_БОРИ_У_АНИ) });
  проверить(зов.ок === true, 'честный зов в друзья не прошёл: ' + (зов.причина || 'без объяснения'));

  // --- 4. Б видит А во входящих, в друзьях пусто
  console.log('4. Б видит входящую заявку от А');
  const списокБпослеЗова = await дверь('/друзья-список', БОРЯ, 'Боря');
  проверить(Array.isArray(списокБпослеЗова.друзья) && списокБпослеЗова.друзья.length === 0,
    'у Бори уже что-то в друзьях, хотя заявку ещё не принимали');
  const входящаяУБори = найтиПоИмени(списокБпослеЗова.входящие, 'Аня');
  проверить(Boolean(входящаяУБори), 'Боря не увидел входящую заявку от Ани');
  const КЛЮЧ_АНИ_У_БОРИ = (входящаяУБори || {}).ключ || '';

  // --- 5. Б принимает заявку
  console.log('5. Б принимает заявку');
  const принял = await дверь('/друзья-принять', БОРЯ, 'Боря', { ключ: испортитьКлюч(КЛЮЧ_АНИ_У_БОРИ) });
  проверить(принял.ок === true, 'принятие честной заявки не прошло');

  // --- 6. Оба видят друг друга в друзьях, не во входящих
  console.log('6. Теперь оба — друзья');
  const списокАпослеПринятия = await дверь('/друзья-список', АНЯ, 'Аня');
  const списокБпослеПринятия = await дверь('/друзья-список', БОРЯ, 'Боря');
  проверить(Boolean(найтиПоИмени(списокАпослеПринятия.друзья, 'Боря')), 'А не увидела Борю в друзьях после принятия');
  проверить(!найтиПоИмени(списокАпослеПринятия.входящие, 'Боря'), 'у А Боря всё ещё висит во входящих — заявка не должна там остаться');
  проверить(Boolean(найтиПоИмени(списокБпослеПринятия.друзья, 'Аня')), 'Б не увидел Аню в друзьях после принятия');
  проверить(!найтиПоИмени(списокБпослеПринятия.входящие, 'Аня'), 'у Б Аня всё ещё висит во входящих после того, как сам её принял');

  // --- 7. Ключи — не голый номер
  console.log('7. Ключ не похож на номер телефона');
  const ключБориУАниВДрузьях = (найтиПоИмени(списокАпослеПринятия.друзья, 'Боря') || {}).ключ || '';
  проверить(typeof ключБориУАниВДрузьях === 'string' && ключБориУАниВДрузьях.length === сервера.ДЛИНА_КЛЮЧА,
    'ключ друга обязан быть длиной ' + сервера.ДЛИНА_КЛЮЧА + ' знаков, а он длиной ' + ключБориУАниВДрузьях.length);
  проверить(/^[0-9a-f]+$/.test(ключБориУАниВДрузьях), 'ключ друга обязан быть шестнадцатеричным словом');
  проверить(ключБориУАниВДрузьях !== String(БОРЯ), 'ключ друга совпал с голым номером Telegram — это утечка');
  проверить(ключБориУАниВДрузьях.indexOf(String(БОРЯ)) === -1 || ключБориУАниВДрузьях.length !== String(БОРЯ).length,
    'ключ друга слишком похож на голый номер телефона');

  // --- 8. Ветка «отклонить»: В↔Б знакомые, Б зовёт В, В отклоняет
  console.log('8. Отклонённая заявка исчезает у обоих');
  const знакомыеБори = (await спросить('/знакомые', { initData: подписьИгрока(БОРЯ, 'Боря') })).тело;
  const ключВитиУБори = ((знакомыеБори && знакомыеБори.знакомые) || [])
    .find(function (з) { return з.имя === 'Витя'; });
  проверить(Boolean(ключВитиУБори), 'Витя не нашёлся в списке знакомых Бори — ветку отклонения не проверить');
  const зовВите = await дверь('/друзья-позвать', БОРЯ, 'Боря', { ключ: испортитьКлюч((ключВитиУБори || {}).ключ || '') });
  проверить(зовВите.ок === true, 'Боря не смог позвать Витю в друзья: ' + (зовВите.причина || 'без объяснения'));

  const списокВитиПередОтказом = await дверь('/друзья-список', ВИТЯ, 'Витя');
  const входящаяУВити = найтиПоИмени(списокВитиПередОтказом.входящие, 'Боря');
  проверить(Boolean(входящаяУВити), 'Витя не увидел входящую заявку от Бори');

  const отказ = await дверь('/друзья-отклонить', ВИТЯ, 'Витя', { ключ: испортитьКлюч((входящаяУВити || {}).ключ || '') });
  проверить(отказ.ок === true, 'отклонение честной заявки не прошло');

  const списокВитиПослеОтказа = await дверь('/друзья-список', ВИТЯ, 'Витя');
  const списокБориПослеОтказа = await дверь('/друзья-список', БОРЯ, 'Боря');
  проверить(!найтиПоИмени(списокВитиПослеОтказа.входящие, 'Боря'), 'у Вити заявка от Бори осталась после отказа');
  проверить(!найтиПоИмени(списокВитиПослеОтказа.друзья, 'Боря'), 'Витя и Боря стали друзьями после отказа — этого быть не должно');
  проверить(!найтиПоИмени(списокБориПослеОтказа.друзья, 'Витя'), 'у Бори Витя попал в друзья после того, как заявку отклонили');

  // --- 9. Ветка «удалить»: А удаляет Б из уже оформленных друзей
  console.log('9. Удаление друга работает для обоих');
  const списокАдоУдаления = await дверь('/друзья-список', АНЯ, 'Аня');
  const ключБориПередУдалением = (найтиПоИмени(списокАдоУдаления.друзья, 'Боря') || {}).ключ || '';
  const удаление = await дверь('/друзья-удалить', АНЯ, 'Аня', { ключ: испортитьКлюч(ключБориПередУдалением) });
  проверить(удаление.ок === true, 'удаление честного друга не прошло');

  const списокАпослеУдаления = await дверь('/друзья-список', АНЯ, 'Аня');
  const списокБпослеУдаления = await дверь('/друзья-список', БОРЯ, 'Боря');
  проверить(!найтиПоИмени(списокАпослеУдаления.друзья, 'Боря'), 'А всё ещё видит Борю в друзьях после удаления');
  проверить(!найтиПоИмени(списокБпослеУдаления.друзья, 'Аня'), 'Боря всё ещё видит Аню в друзьях после того, как его удалили');

  // --- 10. Порченые запросы: отказ без падения
  console.log('10. Порченые запросы получают честный отказ, а не 500');
  const выдуманныйКлюч = 'f'.repeat(сервера.ДЛИНА_КЛЮЧА);
  const позватьВыдуманным = испортить((await спросить('/друзья-позвать', {
    initData: подписьИгрока(ГАЛЯ, 'Галя'), ключ: выдуманныйКлюч
  })).тело);
  проверить(позватьВыдуманным.ок !== true, 'зов ВЫДУМАННЫМ ключом обязан быть отвергнут');
  проверить(typeof позватьВыдуманным.причина === 'string' && позватьВыдуманным.причина.length > 0,
    'при отказе должна быть человеческая причина, а её нет');

  const принятьЧужое = испортить((await спросить('/друзья-принять', {
    initData: подписьИгрока(ГАЛЯ, 'Галя'), ключ: выдуманныйКлюч
  })).тело);
  проверить(принятьЧужое.ок !== true, 'принятие ВЫДУМАННОЙ заявки обязано быть отвергнуто');

  const отклонитьЧужое = испортить((await спросить('/друзья-отклонить', {
    initData: подписьИгрока(ГАЛЯ, 'Галя'), ключ: выдуманныйКлюч
  })).тело);
  проверить(отклонитьЧужое.ок !== true, 'отклонение ВЫДУМАННОЙ заявки обязано быть отвергнуто');

  const удалитьЧужое = испортить((await спросить('/друзья-удалить', {
    initData: подписьИгрока(ГАЛЯ, 'Галя'), ключ: выдуманныйКлюч
  })).тело);
  проверить(удалитьЧужое.ок !== true, 'удаление ВЫДУМАННОГО друга обязано быть отвергнуто');

  const испорченыйОтвет = испортить((await спросить('/друзья-позвать', {
    initData: подписьИгрока(ГАЛЯ, 'Галя'), ключ: 'не-похоже-на-ключ-вовсе'
  })).тело);
  проверить(испорченыйОтвет.ок !== true, 'зов ИСПОРЧЕННЫМ (не шестнадцатеричным) ключом обязан быть отвергнут');

  const безПодписи = испортить((await спросить('/друзья-список', {})).тело);
  проверить(безПодписи.узналиВас !== true, 'дверь /друзья-список ответила БЕЗ ПОДПИСИ Telegram, как будто узнала игрока');

  const пустоеТело = await спросить('/друзья-позвать', null);
  проверить(пустоеТело.код === 200, 'СОВСЕМ ПУСТОЕ ТЕЛО уронило дверь — код ' + пустоеТело.код + ' вместо 200');
  проверить(испортить(пустоеТело.тело).ок !== true, 'дверь ответила «ок» на совсем пустое тело');
}

