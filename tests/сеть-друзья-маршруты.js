/* =====================================================================
   ДРУЗЬЯ: пять новых дверей HTTP (/друзья-позвать, /друзья-принять,
   /друзья-отклонить, /друзья-удалить, /друзья-список).

   Что проверяем. Логика дружбы лежит в server/друзья.js (уже была
   закоммичена и не менялась) — эта проверка не про неё, а про то, что
   пять новых дверей в server/сервер.js правильно с ней разговаривают:
   отдают заявки, принимают, отклоняют, удаляют и не путают, кто кому
   кем приходится. Заодно проверяем то же самое, о чём уже заботится
   /знакомые (tests/зов-знакомого.js): номер Telegram наружу не уходит,
   вместо него — непрозрачный ключ.

   Приём тот же, что в tests/зов-знакомого.js: своя копия сервера
   комнат — В ПАМЯТИ ЭТОГО ЖЕ ПРОЦЕССА (require('../server/сервер.js'),
   сервер.listen на отдельном порту, боевой 8790 не трогаем). Это не
   отдельный процесс — и это не оплошность, а необходимость: сценарий
   просит завести двух «знакомых» напрямую через require('../server/
   знакомые.js'), минуя партию, а это возможно только если проверка и
   сервер делят одну и ту же память. Порознь (сервер — отдельным
   процессом, знакомые — только у проверки) эти двое просто не увидят
   друг друга. Тот же приём — в tests/позвать-в-комнате.js.
   Запись на диск при этом ВЫКЛЮЧЕНА по умолчанию (её включает только
   прямой запуск server/сервер.js — см. включитьЗапись внутри
   require.main === module): мы её нигде не зовём, поэтому эффект
   ровно как у флага «--без-памяти», только без отдельного процесса,
   который делает то же самое. Плюс папка данных на всякий случай
   уведена во временную (ДАННЫЕ_ИГРЫ) — если что-то всё же решит
   записаться, боевые файлы владельца это не заденет.
   initData подписывается вручную тем же HMAC-приёмом, что и в
   tests/зов-знакомого.js (выдуманный токен, поддельная труба вместо
   api.telegram.org — настоящий Telegram здесь ни при чём).

   Что проверяем по шагам:
     1. А и Б — знакомые (через знакомые.запомнитьЗастолье).
     2. У А в /друзья-список пусто и там, и там.
     3. А зовёт Б в друзья ключом из /знакомые — ок:true.
     4. Б видит А во входящих, в друзьях — пусто.
     5. Б принимает заявку тем же ключом — ок:true.
     6. И А, и Б видят друг друга в друзьях (не во входящих).
     7. Ключи в ответе — не голый номер: 32 шестнадцатеричных знака.
     8. Ветка «отклонить»: В↔Б знакомые, Б зовёт В, В отклоняет —
        заявка пропадает у обоих.
     9. Ветка «удалить»: А удаляет Б из уже оформленных друзей —
        дружба пропадает у обоих.
    10. Порченые запросы (левый ключ, без подписи, чужой номер длины) —
        сервер отвечает ок:false с человеческой причиной, не 500-ит.

   Запуск:
       node tests/сеть-друзья-маршруты.js
       node tests/сеть-друзья-маршруты.js 8787      (свой порт)

   Ломающий прогон (проверка обязана покраснеть):
       node tests/сеть-друзья-маршруты.js --сломать
   «--сломать» портит наблюдаемое в памяти самой проверки, не трогая
   сервер: любой ответ двери превращается в «ок:true» с пустыми
   списками, а «настоящий» ключ подменяется на текст, похожий на номер
   телефона. Тогда почти каждая сверка обязана провалиться. Ноль
   провалов при «--сломать» значит, что проверка спит.

   Выход 0 — провалов нет, 1 — есть.
   ===================================================================== */

const path = require('path');
const os = require('os');
const http = require('http');
const crypto = require('crypto');

/* Уводим данные в сторону ДО подключения сервера — на всякий случай,
   см. объяснение выше. Папки может не быть вовсе, это не беда. */
