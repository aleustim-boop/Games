function этоВнутриПроекта(цель) {
  return цель.toLowerCase().startsWith(КОРЕНЬ.toLowerCase() + path.sep);
}

function ломающие(папка) {
  const цель = path.resolve(папка || '');
  if (!папка || этоВнутриПроекта(цель)) {
    console.log('Нужна папка ВНЕ проекта (например, в %TEMP%).');
    process.exit(2);
  }
  fs.mkdirSync(цель, { recursive: true });
  const исходник = fs.readFileSync(НАСТОЯЩИЙ_МОДУЛЬ, 'utf8')
    .replace("require('./папка-данных.js')", 'require(' + JSON.stringify(path.join(КОРЕНЬ, 'server', 'папка-данных.js')) + ')');
  let непокрасневших = 0;
  ПОРЧИ.forEach(function (порча, i) {
    const мест = исходник.split(порча.найти).length - 1;
    if (мест !== 1) {
      console.log('Порча ' + (i + 1) + ' («' + порча.имя + '»): в модуле нашлось мест ' + мест + ' (нужно ровно 1) — проверка устарела.');
      непокрасневших++;
      return;
    }
    const копия = path.join(цель, 'турниры-порча-' + (i + 1) + '.js');
    fs.writeFileSync(копия, исходник.replace(порча.найти, порча.заменить), 'utf8');
    const р = spawnSync(process.execPath, [__filename, '--модуль', копия], { encoding: 'utf8' });
    const последняя = (р.stdout || '').trim().split('\n').filter(function (с) { return с.indexOf('Итого проверок') === 0; })[0] || '(итога нет)';
    const покраснела = р.status === 1;
    console.log('Порча ' + (i + 1) + ' («' + порча.имя + '»): ' + (покраснела ? 'КРАСНАЯ, как и нужно' : 'НЕ ПОКРАСНЕЛА — беда') + '. ' + последняя);
    if (!покраснела) {
      непокрасневших++;
      console.log((р.stdout || '') + (р.stderr || ''));
    }
  });
  console.log('Ломающих запусков: ' + ПОРЧИ.length + ', покраснели: ' + (ПОРЧИ.length - непокрасневших));
  process.exit(непокрасневших === 0 ? 0 : 1);
}

function главная() {
  const аргументы = process.argv.slice(2);
  if (аргументы[0] === '--сломать') return ломающие(аргументы[1]);
  const путьМодуля = аргументы[0] === '--модуль' ? path.resolve(аргументы[1]) : НАСТОЯЩИЙ_МОДУЛЬ;
  const р = прогон(путьМодуля);
  console.log('Итого проверок: ' + р.проверок + ', провалов: ' + р.провалов);
  if (р.провалов > 0) {
    console.log('КРАСНАЯ: есть провалы.');
    process.exit(1);
  }
  console.log('ЗЕЛЁНАЯ: всё в порядке.');
}

