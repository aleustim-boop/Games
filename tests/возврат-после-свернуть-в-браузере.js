async function открыть(контекст, красные, отказыКомнат) {
  const страница = await контекст.newPage();
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    let адрес = '';
    try { адрес = (m_url(м)); } catch (е) { /* нет адреса */ }
    if (/:8790(\/|$)/.test(адрес) || /:8790/.test(м.text())) { отказыКомнат.push(м.text() + ' ' + адрес); return; }
    // Настоящий скрипт telegram.org мы сами не пускаем (на его месте стоит подделка) — это не ошибка игры
    if (/telegram-web-app\.js/.test(адрес)) return;
    красные.push('консоль: ' + м.text() + (адрес ? ' [' + адрес + ']' : ''));
  });
  function m_url(м) { const л = м.location(); return л && л.url ? л.url : ''; }
  await подготовитьПодделку(страница, { версия: '8.0' });
  return страница;
}

const нажатьПоId = (страница, id) =>
  страница.evaluate((и) => { const к = document.getElementById(и); if (!к) return false; к.click(); return true; }, id);
const нажатьПоСелектору = (страница, с) =>
  страница.evaluate((с1) => { const к = document.querySelector(с1); if (!к) return false; к.click(); return true; }, с);

/** Отпечаток положения: что именно было на доске / в руке / открыто. */
function отпечаток(страница, игра) {
  if (игра.дурак) {
    return страница.evaluate(() => {
      const глянуть = (что) => (0, eval)(что);
      let п = null;
      try { п = глянуть('партия'); } catch (е) { return null; }
      if (!п) return null;
      const рука = ((п.руки && п.руки.человек) || []).map((к) => к.масть + '-' + к.имя).sort();
      return 'рука ' + рука.join(',') + '; козырь ' + JSON.stringify(п.козырь) + '; колода ' + (п.колода ? п.колода.length : -1) +
        '; стол ' + (п.стол ? п.стол.length : -1);
    });
  }
  if (игра.casual) {
    return страница.evaluate((ключ) => {
      let с = null;
      try { с = JSON.parse(localStorage.getItem(ключ)).state; } catch (е) { return null; }
      if (!с || !с.open) return null;
      return 'открыто ' + с.open.reduce((а, б) => а + (б ? 1 : 0), 0) + ': ' + с.open.join('') + '; флажков ' + (с.flags || []).reduce((а, б) => а + (б ? 1 : 0), 0);
    }, игра.ключ);
  }
  return страница.evaluate(() => {
    const д = document.getElementById('доска');
    if (!д) return null;
    const места = Array.from(д.querySelectorAll('[data-поле], [data-пункт], [data-бар], [data-полка]'));
    const часть = [];
    for (const м of места) {
      const ключ = м.getAttribute('data-поле') || ('п' + (м.getAttribute('data-пункт') || '')) ||
        ('б' + м.getAttribute('data-бар')) || ('о' + м.getAttribute('data-полка'));
      const фишки = Array.from(м.querySelectorAll('.фишка, .фигура, .шашка'))
        .map((ф) => (ф.getAttribute('data-шашка') || '') + ' ' +
          Array.from(ф.classList).filter((к) => /^(фишка|фигура|шашка)--(белая|чёрная|дамка|король|ферзь|ладья|слон|конь|пешка)/.test(к)).join(','));
      if (фишки.length) часть.push(ключ + '=' + фишки.join('|'));
    }
    return часть.join(';');
  });
}

async function ходЧеловека(страница, игра) {
  if (игра.имя === 'шашки') {
    const а = await нажатьПоСелектору(страница, '#доска [data-поле="c3"]');
    await спать(250);
    const б = await нажатьПоСелектору(страница, '#доска [data-поле="d4"]');
    проверить(а && б, 'шашки: найдены клетки c3 и d4, ход нажат');
  } else if (игра.имя === 'шахматы') {
    const а = await нажатьПоСелектору(страница, '#доска [data-поле="e2"]');
    await спать(250);
    const б = await нажатьПоСелектору(страница, '#доска [data-поле="e4"]');
    проверить(а && б, 'шахматы: найдены клетки e2 и e4, ход нажат');
  } else if (игра.имя === 'нарды') {
    проверить(await нажатьПоId(страница, 'кнопка-бросить'), 'нарды: кнопка «бросить» найдена и нажата');
    await спать(900);
    let сделано = 0;
    for (let круг = 0; круг < 6; круг++) {
      const взяли = await страница.evaluate(() => { const ш = document.querySelector('.шашка--можно-взять'); if (!ш) return false; ш.click(); return true; });
      if (!взяли) break;
      await спать(250);
      const пошли = await страница.evaluate(() => { const ц = document.querySelector('.пункт--можно'); if (!ц) return false; ц.click(); return true; });
      if (!пошли) break;
      сделано++;
      await спать(700);
    }
    await страница.evaluate(() => { const к = document.getElementById('кнопка-закончить-ход'); if (к && !к.disabled && к.offsetParent !== null) к.click(); });
    проверить(сделано > 0, 'нарды: человек походил шашками (ходов: ' + сделано + ')');
  }
}

async function ждатьБота(страница, игра) {
  await спать(1200);
  for (let i = 0; i < 40; i++) {
    const готово = await страница.evaluate((имя) => {
      if (имя === 'нарды') {
        const к = document.getElementById('кнопка-бросить');
        return Boolean(к && !к.disabled && document.querySelectorAll('#кубики [data-очки]').length === 0);
      }
      const э = document.getElementById('строка-хода');
      return Boolean(э && /ваш ход|ваш|ход белых/i.test(э.textContent));
    }, игра.имя);
    if (готово) { await спать(500); return true; }
    await спать(500);
  }
  return false;
}

/** Довести партию до непустого положения настоящими нажатиями. */
async function начатьПартию(страница, игра) {
  if (игра.дурак) {
    await страница.goto(ОСНОВА + 'index.html', { waitUntil: 'load' });
    await страница.waitForSelector('#экран-витрины.экран--виден', { timeout: 10000 });
    проверить(await нажатьПоId(страница, 'кнопка-игра-дурак'), 'дурак: плитка дурака на витрине найдена и нажата');
    await страница.waitForSelector('#экран-лобби.экран--виден', { timeout: 10000 });
    проверить(await нажатьПоId(страница, 'лобби-боты'), 'дурак: карточка «Играть с ботом» найдена и нажата');
    await страница.waitForSelector('#экран-путь-правила.экран--виден', { timeout: 10000 });
    await страница.click('.экран--виден [data-путь="далее"]');
    await страница.waitForSelector('#экран-путь-игроки.экран--виден', { timeout: 10000 });
    await страница.click('.экран--виден [data-путь="далее"]');
    await страница.waitForSelector('#экран-путь-настройки.экран--виден', { timeout: 10000 });
    await страница.click('#путь-начать');
    await страница.waitForSelector('#экран-игры.экран--виден', { timeout: 10000 });
    await страница.waitForSelector('#карты-человека .карта', { timeout: 10000 });
    await страница.addScriptTag({ path: path.join(__dirname, 'автоигрок-в-браузере.js') });
    await страница.evaluate(() => { window.Автоигрок.начать(0.6, false, 0); });
    let готово = false;
    for (let i = 0; i < 20 && !готово; i++) {
      await спать(700);
      готово = await страница.evaluate(() => {
        try { const п = (0, eval)('партия'); return Boolean(п && !п.завершена && (0, eval)('ходовЧеловека') >= 1 && п.колода.length < 24); } catch (е) { return false; }
      });
    }
    await страница.evaluate(() => { window.Автоигрок.стоп(); });
    await спать(2500);   // бот доиграл отложенный ход
    проверить(готово, 'дурак: человек сделал хотя бы один настоящий ход');
    return;
  }
  await страница.goto(ОСНОВА + игра.файл, { waitUntil: 'load' });
  await спать(900);
  if (игра.casual) {
    await страница.click('#play');
    await страница.waitForFunction(() => { const э = document.getElementById('экран-игры'); return Boolean(э && !э.hidden); }, null, { timeout: 10000 });
    await спать(500);
    const клетка = страница.locator('[data-cell="20"]');
    проверить((await клетка.count()) === 1, 'сапёр: клетка поля найдена (ноль — провал)');
    await клетка.click();
    await спать(700);
    return;
  }
  проверить(await нажатьПоId(страница, 'лобби-боты'), игра.имя + ': карточка «Играть с ботом» найдена и нажата');
  await спать(400);
  const начать = игра.имя === 'шахматы' ? 'лобби-бот-начать' : 'кнопка-с-ботом';
  проверить(await нажатьПоId(страница, начать), игра.имя + ': «' + начать + '» найдена и нажата');
  await спать(900);
  await ходЧеловека(страница, игра);
  проверить(await ждатьБота(страница, игра), игра.имя + ': бот ответил, ход снова за человеком');
}

/** Где мы и виден ли стол партии. */
function осмотреться(страница, игра) {
  return страница.evaluate((г) => {
    let имя = '';
    try { имя = decodeURIComponent(location.pathname).split('/').pop() || 'index.html'; } catch (е) { имя = location.pathname; }
    const э = document.getElementById(г.стол);
    const виден = Boolean(э && !э.hidden && (э.classList.contains('экран--виден') || г.casual) && э.offsetWidth > 0);
    const лобби = document.getElementById('экран-лобби');
    const витрина = document.getElementById('экран-витрины');
    return {
      страница: имя, запрос: location.search,
      стол: виден,
      лоббиВидно: Boolean(лобби && лобби.classList.contains('экран--виден')),
      витринаВидна: Boolean(витрина && витрина.classList.contains('экран--виден')),
      метка: localStorage.getItem('resume_at')
    };
  }, игра);
}

async function сыграть(браузер, игра) {
  console.log('\n=== ' + игра.имя + ' (390 px) ===');
  const красные = [];
  const отказыКомнат = [];
  const контекст = await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, deviceScaleFactor: 2 });
  try {
    const страница = await открыть(контекст, красные, отказыКомнат);

    // 1. партия и ход
    await начатьПартию(страница, игра);
    const до = await отпечаток(страница, игра);
    проверить(Boolean(до) && до.length > 15, игра.имя + ': отпечаток положения до «Свернуть» снят (' + String(до).slice(0, 70) + ')');
    if (игра.casual) проверить(/открыто [1-9]/.test(до || ''), 'сапёр: после нажатия на клетку открыта хотя бы одна клетка');

    // 2. «Свернуть»
    await страница.waitForSelector('.свернуть-окно', { state: 'visible', timeout: 8000 }).catch(() => {});
    const кнопок = await страница.locator('.свернуть-окно:visible').count();
    проверить(кнопок === 1, игра.имя + ': видна настоящая кнопка «Свернуть» (найдено ' + кнопок + ', ноль — провал)');
    if (кнопок === 1) await страница.locator('.свернуть-окно').click();
    await спать(500);
    const после = await страница.evaluate(() => ({
      close: window.ПоддельныйТелеграм.журнал.filter((с) => с === 'close').length,
      метка: localStorage.getItem('resume_at')
    }));
    проверить(после.close === 1, игра.имя + ': close вызван ровно один раз (вызовов ' + после.close + ')');
    let метка = null;
    try { метка = JSON.parse(после.метка); } catch (е) { /* нет метки */ }
    проверить(Boolean(метка) && метка.p === игра.файл, игра.имя + ': метка записана на страницу «' + игра.файл + '» (метка: ' + после.метка + ')');
    if (игра.дурак) проверить(Boolean(метка) && метка.d === true, 'дурак: в метке d:true (открыт дурак, а не витрина)');
    else проверить(Boolean(метка) && метка.d === false, игра.имя + ': в метке d:false');
    await страница.close();   // как будто приложение закрылось

    // 3. открыть заново — без нажатий
    const страница2 = await открыть(контекст, красные, отказыКомнат);
    const началоМс = Date.now();
    await страница2.goto(ОСНОВА, { waitUntil: 'load' });
    const ссн = await страница2.evaluate(() => sessionStorage.length);
    console.log('  (вторая вкладка открыта на «' + ОСНОВА + '», в sessionStorage записей: ' + ссн + ')');
    let вернулись = false;
    let вид = null;
    while (Date.now() - началоМс < ЖДАТЬ_ВОЗВРАТ_МС) {
      await спать(250);
      try { вид = await осмотреться(страница2, игра); } catch (е) { continue; }   // страница как раз переходит
      if (вид.страница === игра.файл && вид.стол && !вид.лоббиВидно && (!игра.дурак || вид.запрос.indexOf('game=durak') >= 0 || true)) { вернулись = true; break; }
    }
    const секунд = ((Date.now() - началоМс) / 1000).toFixed(1);
    проверить(вернулись, игра.имя + ': без единого нажатия вернулась на экран партии за ' + секунд + ' с' +
      (вернулись ? '' : ' — остались в лобби/на витрине: ' + JSON.stringify(вид)));
    if (вернулись) {
      await спать(900);
      const после2 = await отпечаток(страница2, игра);
      проверить(после2 === до, игра.имя + ': положение то же, что до «Свернуть»' +
        (после2 === до ? '' : '\n      было:  ' + до + '\n      стало: ' + после2));
    }
    fs.mkdirSync(ПАПКА_СНИМКОВ, { recursive: true });
    const снимок = path.join(ПАПКА_СНИМКОВ, игра.имя + (СЛОМАТЬ ? '-ломающий' : '') + '.png');
    await страница2.screenshot({ path: снимок });
    проверить(fs.statSync(снимок).size > 1000, игра.имя + ': снимок записан: ' + снимок);

    // 4. «В меню» — обратно не кидает
    if (вернулись) {
      let ушли = false;
      if (игра.casual) {
        for (let i = 0; i < 3 && !ушли; i++) {
          const нажали = await нажатьПоId(страница2, 'back');
          if (!нажали) break;
          await спать(1200);
          const в = await осмотреться(страница2, игра).catch(() => null);
          ушли = Boolean(в && в.страница === 'index.html');
        }
      } else {
        const открыли = await нажатьПоId(страница2, 'кнопка-игра-ещё');
        проверить(открыли, игра.имя + ': кнопка «⋯» (кнопка-игра-ещё) найдена и нажата');
        await спать(500);
        const меню = await нажатьПоId(страница2, 'кнопка-лист-игры-меню');
        проверить(меню, игра.имя + ': строка «В меню» (кнопка-лист-игры-меню) найдена и нажата');
        await спать(900);
        // Если игра спрашивает «Завершить партию?» — подтверждаем, как это сделал бы игрок
        await нажатьПоСелектору(страница2, '.плашка-завершить:not(.скрыт) .кнопка--опасная');
        await спать(1500);
        // «В меню» из партии ведёт в лобби самой игры; там держим паузу — в стол обратно кидать нельзя
        const влобби = await осмотреться(страница2, игра).catch(() => null);
        проверить(Boolean(влобби) && влобби.лоббиВидно && !влобби.стол,
          игра.имя + ': «В меню» привело в лобби игры, стол закрыт (сейчас: ' + JSON.stringify(влобби) + ')');
        await спать(3000);
        const влобби2 = await осмотреться(страница2, игра).catch(() => null);
        проверить(Boolean(влобби2) && влобби2.лоббиВидно && !влобби2.стол,
          игра.имя + ': 3 секунды спустя всё ещё в лобби — в партию не кидает (' + JSON.stringify(влобби2) + ')');
        // и «К выбору игры» (‹) из лобби — на витрину
        const назад = await нажатьПоСелектору(страница2, '#экран-лобби button[aria-label="К выбору игры"]');
        проверить(назад, игра.имя + ': кнопка «‹ К выбору игры» в лобби найдена и нажата');
        await спать(1200);
      }
      let в1 = null;
      for (let i = 0; i < 10; i++) {
        try { в1 = await осмотреться(страница2, игра); } catch (е) { в1 = null; }
        if (в1 && в1.страница === 'index.html' && в1.витринаВидна) break;
        await спать(500);
      }
      проверить(Boolean(в1) && в1.страница === 'index.html' && в1.витринаВидна && !в1.стол,
        игра.имя + ': «В меню» привело на витрину (сейчас: ' + JSON.stringify(в1) + ')');
      await спать(5000);
      let в2 = null;
      try { в2 = await осмотреться(страница2, игра); } catch (е) { в2 = null; }
      проверить(Boolean(в2) && в2.страница === 'index.html' && в2.витринаВидна && !в2.стол && !в2.лоббиВидно,
        игра.имя + ': через 5 секунд всё ещё на витрине — обратно в игру не кидает (' + JSON.stringify(в2) + ')');
      проверить(Boolean(в2) && в2.метка === null, игра.имя + ': метки в памяти нет');
    }
    await страница2.close();
  } finally {
    await контекст.close();
  }
  if (отказыКомнат.length) console.log('  (отказов соединения с сервером комнат 8790, не считаются: ' + отказыКомнат.length + ')');
  проверить(красные.length === 0, игра.имя + ': консоль без красных ошибок' + (красные.length ? ' — ' + красные.join(' | ') : ''));
}

