/* =======================================================================
   ЛОМАЮЩИЙ ПРОГОН: копия проекта во временной папке, шашки.html без
   строки подключения js/подбор-экран.js — обязан покраснеть.
   ======================================================================= */

function сделатьКопиюПроекта(папка) {
  for (const частьПапка of ['server', 'js', 'img', 'шрифты']) {
    const откуда = path.join(ПРОЕКТ, частьПапка);
    if (!fs.existsSync(откуда)) continue;
    fs.cpSync(откуда, path.join(папка, частьПапка), {
      recursive: true,
      filter: function (откудаФайл) {
        const имя = path.basename(откудаФайл);
        return имя !== 'данные' && имя !== 'node_modules';
      }
    });
  }
  for (const файл of fs.readdirSync(ПРОЕКТ)) {
    if (файл.endsWith('.html') || файл.endsWith('.css')) {
      fs.copyFileSync(path.join(ПРОЕКТ, файл), path.join(папка, файл));
    }
  }
}

function ломать() {
  console.log('=== Ломающий прогон: подбор шашек и нард из браузера — обязан покраснеть ===');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'подбор-игр-браузер-лом-'));
  сделатьКопиюПроекта(папка);

  const файлШашки = path.join(папка, 'шашки.html');
  let текст = fs.readFileSync(файлШашки, 'utf8');
  const строкаПодключения = '<script src="js/подбор-экран.js?v=1"></script>';
  if (текст.indexOf(строкаПодключения) === -1) {
    console.log('ПРОВАЛ: в копии шашки.html не нашлась строка «' + строкаПодключения + '» — портить нечего (проверку саму нечем покраснить)');
    process.exit(1);
  }
  текст = текст.split(строкаПодключения).join('');
  fs.writeFileSync(файлШашки, текст, 'utf8');
  console.log('Порченая копия: ' + папка + ' (в шашки.html вырезана строка подключения js/подбор-экран.js)');

  const прогон = spawnSync(process.execPath, [__filename, '--корень', папка], { encoding: 'utf8', timeout: 180000 });
  console.log('\n----- вывод ломающего прогона -----');
  console.log(прогон.stdout || '');
  if (прогон.stderr) console.log('stderr: ' + прогон.stderr);
  console.log('------------------------------------');

  const покраснел = прогон.status === 1;
  console.log(покраснел
    ? 'ЛОМАЮЩИЙ ПРОГОН ПОКРАСНЕЛ, КАК И ДОЛЖЕН (код выхода ' + прогон.status + ').'
    : 'ПРОВАЛ: ломающий прогон остался зелёным (код выхода ' + прогон.status + ') — проверка не ловит поломку!');
  console.log('Копия оставлена для разбора: ' + папка);
  process.exit(покраснел ? 0 : 1);
}

/* =======================================================================
   Обычный прогон
   ======================================================================= */

async function прогнать(корень) {
  /* На настоящем проекте — постоянные снимки в tests/снимки/, их видит
     смотритель. На чужой (временной) копии — свои снимки внутри самой
     этой копии: их видно в выводе при разборе ломающего прогона, но они
     никогда не пересекаются с постоянными файлами проекта. */
  const этоНастоящийПроект = path.resolve(корень).toLowerCase() === path.resolve(ПРОЕКТ).toLowerCase();
  const папкаСнимков = этоНастоящийПроект ? ПАПКА_СНИМКОВ_ПРОЕКТА : path.join(корень, '_снимки-ломающего-прогона');
  fs.mkdirSync(папкаСнимков, { recursive: true });
  console.log('=== Подбор шашек и нард — проверка в браузере (playwright) ===');
  console.log('корень: ' + корень);
  console.log('снимки: ' + папкаСнимков + (этоНастоящийПроект ? '' : ' (это копия, не tests/снимки/ проекта)'));
  console.log('файлы: http://127.0.0.1:' + ПОРТ_ФАЙЛОВ + ' (не боевой), комнаты: http://127.0.0.1:' + ПОРТ_КОМНАТ + ' (не боевой 8790)\n');

  const файловый = await поднятьФайловыйСервер(корень, ПОРТ_ФАЙЛОВ);
  const { сервер: серверКомнат, подбор } = await поднятьСерверКомнат(корень, ПОРТ_КОМНАТ);

  let браузер = null;
  try {
    браузер = await chromium.launch();
    await шашкиОжиданиеИОтмена(браузер, path.join(папкаСнимков, 'подбор-шашки-ожидание-390.png'));
    await двоеШашекЗаСтолом(браузер, path.join(папкаСнимков, 'подбор-шашки-стол-390.png'));
    await нардыОдиночкаСБотом(браузер, подбор, path.join(папкаСнимков, 'подбор-нарды-бот-390.png'));
    await дуракКакРаньше(браузер);
  } finally {
    if (браузер) await браузер.close();
    файловый.kill();
    серверКомнат.close();
    console.log('\nФайловый сервер (' + ПОРТ_ФАЙЛОВ + ') погашен по PID ' + файловый.pid + ', сервер комнат (' + ПОРТ_КОМНАТ + ') закрыт.');
  }

  console.log('\nИтого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
  process.exit(провалов > 0 ? 1 : 0);
}

function доводПосле(имя) {
  const где = process.argv.indexOf(имя);
  return где !== -1 ? process.argv[где + 1] : null;
}

if (process.argv.includes('--сломать')) {
  ломать();
} else {
  const корень = path.resolve(доводПосле('--корень') || ПРОЕКТ);
  прогнать(корень).catch(function (е) {
    console.error('ПРОВАЛ ЗАПУСКА: ' + (е && е.stack || е));
    process.exit(1);
  });
}
