async function новаяСтраница(браузер, настройкиПодделки) {
  const контекст = await браузер.newContext({ viewport: { width: 390, height: 844 } });
  const страница = await контекст.newPage();
  const ошибки = [];
  страница.on('pageerror', function (о) { ошибки.push('исключение: ' + о.message); });
  страница.on('console', function (с) {
    if (с.type() === 'error' && !/Failed to load resource/.test(с.text())) ошибки.push('консоль: ' + с.text());
  });
  await подготовитьПодделку(страница, настройкиПодделки);
  return { контекст: контекст, страница: страница, ошибки: ошибки };
}

async function нажать(страница, id) {
  return страница.evaluate(function (id) {
    const у = document.getElementById(id);
    if (!у) return false;
    у.click();
    return true;
  }, id);
}

async function видноЛи(страница, id) {
  return страница.evaluate(function (id) {
    const у = document.getElementById(id);
    return Boolean(у && !у.classList.contains('скрыт') && у.offsetParent !== null);
  }, id);
}

async function экранВиден(страница, id) {
  return страница.evaluate(function (id) {
    const у = document.getElementById(id);
    return Boolean(у && у.classList.contains('экран--виден'));
  }, id);
}

/** Состояние экрана ожидания подбора: узел не найден — это честный провал,
    а не тихий пропуск (проверка сама подставит пустые значения). */
async function видЭкранаПодбора(страница) {
  return страница.evaluate(function () {
    const экран = document.getElementById('экран-подбор-соперника');
    if (!экран) return { экранВиден: false, непустой: false, ожиданиеТекст: '', отменаВидна: false };
    const ожидание = document.getElementById('подбор-ожидание');
    const отмена = document.getElementById('подбор-отмена');
    const видно = function (у) { return Boolean(у && !у.classList.contains('скрыт') && у.offsetParent !== null); };
    return {
      экранВиден: экран.classList.contains('экран--виден'),
      непустой: экран.children.length > 0,
      ожиданиеТекст: ожидание ? ожидание.textContent.trim() : '',
      отменаВидна: видно(отмена)
    };
  });
}

/** Дождаться, что на экране появилась #доска нужной игры (класс + не пуста
    + правда видна пальцу — offsetParent не null). Экран-обёртку по id не
    ищем: у нард и дурака он «экран-игры», а у шашек — отдельно «экран-
    шашек» (проверено в шашки.html, нарды.html, index.html) — раздвоенное
    имя для одной и той же роли, но раз это устройство разметки самой
    игры, а не повод падать проверке, судим по тому, что реально видно. */
async function ждатьДоску(страница, классДоски, таймаутМс) {
  try {
    await страница.waitForFunction(function (класс) {
      const доска = document.getElementById('доска');
      return Boolean(доска && доска.classList.contains(класс) &&
        доска.children.length > 0 && доска.offsetParent !== null);
    }, классДоски, { timeout: таймаутМс || 8000 });
    return true;
  } catch (сбой) {
    return false;
  }
}

/** Код стола, который js/сеть.js сохранил в localStorage под ключом «room_*».
    Ключ ищем по началу имени, а не по точному имени игры — переименовали
    латинское имя игры, поиск не должен молча вернуть null. */
async function кодСохранённойКомнаты(страница) {
  return страница.evaluate(function () {
    try {
      const ключ = Object.keys(window.localStorage).find(function (к) { return к.indexOf('room_') === 0; });
      if (!ключ) return null;
      const запись = JSON.parse(window.localStorage.getItem(ключ) || '{}');
      return запись && запись.код ? String(запись.код) : null;
    } catch (сбой) {
      return null;
    }
  });
}

/* ---------------------------------------------------------------------
   Сценарий 1. Шашки: «Найти игру» → ожидание → «Отменить»
   --------------------------------------------------------------------- */
async function шашкиОжиданиеИОтмена(браузер, путьСнимка) {
  console.log('\n=== Шашки: «Найти игру» → экран ожидания → «Отменить» ===');
  const { контекст, страница, ошибки } = await новаяСтраница(браузер, { подпись: initDataИгрока(900101, 'Аня') });
  await страница.goto(АДРЕС_ФАЙЛОВ + 'шашки.html?сервер=' + encodeURIComponent(АДРЕС_КОМНАТ));
  await страница.waitForTimeout(700);

  проверить(await нажать(страница, 'лобби-найти-игру'), 'Шашки: карточка «Играть онлайн» (#лобби-найти-игру) нашлась и нажалась');
  await страница.waitForTimeout(500);
  проверить(await экранВиден(страница, 'экран-открытые-столы'), 'Шашки: экран «Играть онлайн» открылся');
  проверить(await видноЛи(страница, 'открытые-столы-подбор'), 'Шашки: кнопка «Найти игру» на экране «Играть онлайн» видна');

  проверить(await нажать(страница, 'открытые-столы-подбор'), 'Шашки: кнопка «Найти игру» нажалась');
  await страница.waitForTimeout(800);

  const вид = await видЭкранаПодбора(страница);
  проверить(вид.экранВиден, 'Шашки: экран ожидания (#экран-подбор-соперника) открылся');
  проверить(вид.непустой, 'Шашки: экран ожидания не пустой (есть содержимое)');
  проверить(вид.ожиданиеТекст.length > 0 && !/ошиб/i.test(вид.ожиданиеТекст),
    'Шашки: текст на экране — «' + вид.ожиданиеТекст + '», без слова «ошибка»');
  проверить(вид.отменаВидна, 'Шашки: кнопка «Отменить» видна');

  if (путьСнимка) {
    await страница.screenshot({ path: путьСнимка });
    console.log('  снимок: ' + путьСнимка);
  }

  проверить(await нажать(страница, 'подбор-отмена'), 'Шашки: кнопка «Отменить» нажалась');
  await страница.waitForTimeout(500);
  проверить(await экранВиден(страница, 'экран-открытые-столы'), 'Шашки: «Отменить» вернула на экран «Играть онлайн»');

  проверить(ошибки.length === 0, 'Шашки: красных ошибок в консоли нет' + (ошибки.length ? ' — ' + ошибки.join(' | ') : ''));
  await контекст.close();
}

/* ---------------------------------------------------------------------
   Сценарий 2. Шашки: двое «Найти игру» — один стол
   --------------------------------------------------------------------- */
async function двоеШашекЗаСтолом(браузер, путьСнимка) {
  console.log('\n=== Шашки: двое жмут «Найти игру» — сведены за один стол ===');
  const а = await новаяСтраница(браузер, { подпись: initDataИгрока(900102, 'Боря') });
  const б = await новаяСтраница(браузер, { подпись: initDataИгрока(900103, 'Вера') });

  await а.страница.goto(АДРЕС_ФАЙЛОВ + 'шашки.html?сервер=' + encodeURIComponent(АДРЕС_КОМНАТ));
  await б.страница.goto(АДРЕС_ФАЙЛОВ + 'шашки.html?сервер=' + encodeURIComponent(АДРЕС_КОМНАТ));
  await а.страница.waitForTimeout(500);
  await б.страница.waitForTimeout(500);

  проверить(await нажать(а.страница, 'лобби-найти-игру'), 'Шашки (двое): у первого нажалась карточка «Играть онлайн»');
  await а.страница.waitForTimeout(300);
  проверить(await нажать(а.страница, 'открытые-столы-подбор'), 'Шашки (двое): первый нажал «Найти игру»');
  await а.страница.waitForTimeout(500);   // первый должен успеть встать в очередь раньше второго

  проверить(await нажать(б.страница, 'лобби-найти-игру'), 'Шашки (двое): у второго нажалась карточка «Играть онлайн»');
  await б.страница.waitForTimeout(300);
  проверить(await нажать(б.страница, 'открытые-столы-подбор'), 'Шашки (двое): второй нажал «Найти игру»');

  const [видноА, видноБ] = await Promise.all([
    ждатьДоску(а.страница, 'доска-шашек', 10000),
    ждатьДоску(б.страница, 'доска-шашек', 10000)
  ]);
  проверить(видноА, 'Шашки (двое): первый видит стол шашек (не дурака) после сведения');
  проверить(видноБ, 'Шашки (двое): второй видит стол шашек (не дурака) после сведения');

  const кодА = await кодСохранённойКомнаты(а.страница);
  const кодБ = await кодСохранённойКомнаты(б.страница);
  проверить(Boolean(кодА) && кодА === кодБ, 'Шашки (двое): у обоих один и тот же код стола (вышло «' + кодА + '» и «' + кодБ + '»)');

  if (путьСнимка) {
    await б.страница.screenshot({ path: путьСнимка });
    console.log('  снимок: ' + путьСнимка);
  }

  проверить(а.ошибки.length === 0, 'Шашки (двое): у первого красных ошибок в консоли нет' + (а.ошибки.length ? ' — ' + а.ошибки.join(' | ') : ''));
  проверить(б.ошибки.length === 0, 'Шашки (двое): у второго красных ошибок в консоли нет' + (б.ошибки.length ? ' — ' + б.ошибки.join(' | ') : ''));

  await а.контекст.close();
  await б.контекст.close();
}

/* ---------------------------------------------------------------------
   Сценарий 3. Нарды: одиночка ждёт — сервер подсаживает бота
   --------------------------------------------------------------------- */
async function нардыОдиночкаСБотом(браузер, подбор, путьСнимка) {
  console.log('\n=== Нарды: одиночка ждёт — сервер подсаживает бота ===');
  подбор.подменитьПорогОжиданияДляПроверки(300);   // порог до бота: 300 мс вместо 20 с
  try {
    const { контекст, страница, ошибки } = await новаяСтраница(браузер, { подпись: initDataИгрока(900104, 'Гоша') });
    await страница.goto(АДРЕС_ФАЙЛОВ + 'нарды.html?сервер=' + encodeURIComponent(АДРЕС_КОМНАТ));
    await страница.waitForTimeout(500);

    проверить(await нажать(страница, 'лобби-найти-игру'), 'Нарды: карточка «Играть онлайн» нашлась и нажалась');
    await страница.waitForTimeout(400);
    проверить(await нажать(страница, 'открытые-столы-подбор'), 'Нарды: кнопка «Найти игру» нажалась');

    const видноДоску = await ждатьДоску(страница, 'доска-нард', 15000);
    проверить(видноДоску, 'Нарды: одиночка дождалась бота — виден стол нард (класс «доска-нард»)');

    if (путьСнимка) {
      await страница.screenshot({ path: путьСнимка });
      console.log('  снимок: ' + путьСнимка);
    }

    проверить(ошибки.length === 0, 'Нарды: красных ошибок в консоли нет' + (ошибки.length ? ' — ' + ошибки.join(' | ') : ''));
    await контекст.close();
  } finally {
    подбор.подменитьПорогОжиданияДляПроверки();   // вернуть обычный порог
  }
}

