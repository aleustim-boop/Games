/**
 * Сделать копию server/посещения.js во временной папке с указанными
 * текстовыми заменами (одна прицельная поломка на вариант). Рядом
 * кладётся server/папка-данных.js — копия require'ит его же как соседа.
 */
function сделатьКопиюСЗаменами(замены, суффикс) {
  let текст = fs.readFileSync(ИСХОДНИК, 'utf8');
  for (const { откуда, куда } of замены) {
    const новыйТекст = текст.split(откуда).join(куда);
    if (новыйТекст === текст) {
      return { ошибка: 'поломка "' + суффикс + '" не применилась: не найден фрагмент ' + JSON.stringify(откуда.slice(0, 70)) + '…' };
    }
    текст = новыйТекст;
  }
  // Копия лежит не в server/, поэтому относительный путь к реестру игр
  // заменяем настоящим (это не поломка, а перенос).
  текст = текст.split("require('../js/игры-реестр.js')").join('require(' + JSON.stringify(path.join(КОРЕНЬ, 'js', 'игры-реестр.js')) + ')');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'посещения-сломать-' + суффикс + '-'));
  const файл = path.join(папка, 'посещения.js');
  fs.copyFileSync(path.join(КОРЕНЬ, 'server', 'папка-данных.js'), path.join(папка, 'папка-данных.js'));
  fs.writeFileSync(файл, текст, 'utf8');
  return { путь: файл };
}

