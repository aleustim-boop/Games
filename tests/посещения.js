/* =====================================================================
   Проверка server/посещения.js — учёт посещений игры по пульсу браузера.
   Модуль создаётся фабрикой создать({файл, часы}) — тут файл всегда
   во временной папке (os.tmpdir), а часы поддельные и двигаются рукой.

   Зафиксированное правило (задание разрешает выбрать самому и
   зафиксировать): минутыПоИграм копится по фактическим промежуткам
   между пульсами, «+1 минута» в конце сессии — только отметка времени
   и на счётчик минут не влияет. Поэтому 3 пульса с шагом 60 с дают
   РОВНО 2 минуты в сессии, не 3.

   Сценарии обычного прогона:
     1.  3 пульса подряд (шаг 60 с) → одна сессия, минут = 2.
     2.  Пауза 4 мин после того → новая сессия (заходов = 2 за сегодня).
     3.  Сессии старше 30 дней не попадают в сводку.
     4.  Пульс с чужой игрой («футбол») отброшен — учесть() вернул false.
     5.  Номер принимается, только если ЦЕЛИКОМ из цифр: «abc» и
         «a9b0b0» отброшены (второй раньше ошибочно обрезался до «900» и
         принимался), номер с пробелами по краям — принят после trim.
     6.  Пульс чаще 30 с от того же номера отброшен, минуты не растут.
     7.  «Сейчас» пустеет через 3 мин тишины.
     8.  Запись на диск и чтение обратно новым экземпляром модуля.
     9.  Повреждённый файл на диске не роняет модуль.
     10. Смена игры внутри одной сессии — минуты ДО смены уходят
         ПРЕЖНЕЙ игре, минуты ПОСЛЕ — новой (раньше все минуты сессии
         задним числом уезжали новой игре).
     11. 201-я сессия одного номера за день отброшена (лимит 200).
     12. Управляющие знаки (\n, \x00) вырезаются из имени до обрезки.
     13. Сдвиг часов назад (как при сбое NTP): пульс отклонён, минуты не
         уходят в минус и не меняются.
     14. После прибраться() номер, у которого не осталось сессий,
         пропадает и из карты правила частоты (иначе она растёт без
         предела).

     15. Игры берутся из реестра: «монополия», «покер» и все ключи реестра приняты.
     16. Гость: есть в «гости», нет в списках людей; кривой ид, чужая игра, частый пульс отброшены.
     17. Потолок: 2001-й новый гость за сутки отброшен, известный продолжает.
     18. числаЗаДни: люди и гости раздельно, минуты по играм.
     20. Старый посещения.json (без «гости») грузится без потерь.
     21. Гости переживают запись на диск, имён в файле нет.

   Ломающий запуск --сломать (варианты 15-21 добавлены этапом А1): для каждого из пунктов 1, 5, 10, 11, 12,
   13, 14 делается СВОЯ копия server/посещения.js во временной папке с
   одной прицельной поломкой (текстовой заменой), и прогон сценариев 1-7
   и 10-14 повторяется против неё — соответствующий сценарий обязан
   покраснеть.

   Запуск:
       node tests/посещения.js
       node tests/посещения.js --сломать
   ===================================================================== */

const path = require('path');
