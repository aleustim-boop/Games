/* =====================================================================
   Проверка server/посещения.js — учёт посещений игры по пульсу браузера.
   Модуль создаётся фабрикой создать({файл, часы}) — тут файл всегда
   во временной папке (os.tmpdir), а часы поддельные и двигаются рукой.

   Зафиксированное правило (задание разрешает выбрать самому и
   зафиксировать): минутыПоИграм копится по фактическим промежуткам
   между пульсами, «+1 минута» в конце сессии — только отметка времени
   и на счётчик минут не влияет. Поэтому 3 пульса с шагом 60 с дают
   РОВНО 2 минуты в сессии, не 3.

   Сценарии обычного прогона:
     1.  3 пульса подряд (шаг 60 с) → одна сессия, минут = 2.
     2.  Пауза 4 мин после того → новая сессия (заходов = 2 за сегодня).
     3.  Сессии старше 30 дней не попадают в сводку.
     4.  Пульс с чужой игрой («футбол») отброшен — учесть() вернул false.
     5.  Номер принимается, только если ЦЕЛИКОМ из цифр: «abc» и
         «a9b0b0» отброшены (второй раньше ошибочно обрезался до «900» и
         принимался), номер с пробелами по краям — принят после trim.
     6.  Пульс чаще 30 с от того же номера отброшен, минуты не растут.
     7.  «Сейчас» пустеет через 3 мин тишины.
     8.  Запись на диск и чтение обратно новым экземпляром модуля.
     9.  Повреждённый файл на диске не роняет модуль.
     10. Смена игры внутри одной сессии — минуты ДО смены уходят
         ПРЕЖНЕЙ игре, минуты ПОСЛЕ — новой (раньше все минуты сессии
         задним числом уезжали новой игре).
     11. 201-я сессия одного номера за день отброшена (лимит 200).
     12. Управляющие знаки (\n, \x00) вырезаются из имени до обрезки.
     13. Сдвиг часов назад (как при сбое NTP): пульс отклонён, минуты не
         уходят в минус и не меняются.
     14. После прибраться() номер, у которого не осталось сессий,
         пропадает и из карты правила частоты (иначе она растёт без
         предела).

   Ломающий запуск --сломать: для каждого из пунктов 1, 5, 10, 11, 12,
   13, 14 делается СВОЯ копия server/посещения.js во временной папке с
   одной прицельной поломкой (текстовой заменой), и прогон сценариев 1-7
   и 10-14 повторяется против неё — соответствующий сценарий обязан
   покраснеть.

   Запуск:
       node tests/посещения.js
       node tests/посещения.js --сломать
   ===================================================================== */

const path = require('path');
const os = require('os');
const fs = require('fs');

const СЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;
const КОРЕНЬ = path.join(__dirname, '..');
const ИСХОДНИК = path.join(КОРЕНЬ, 'server', 'посещения.js');

const МИНУТА = 60 * 1000;

/* --- Мелкая обвязка проверок, как в других проверках проекта. --- */
function новыйПрогон() {
  const провалы = [];
  let проверок = 0;
  const провалыПоСценариям = {};
  let текущийСценарий = 0;

  function сценарий(н) { текущийСценарий = н; }
  function проверить(условие, что) {
    проверок++;
    if (!условие) {
      провалы.push('[' + текущийСценарий + '] ' + что);
      провалыПоСценариям[текущийСценарий] = (провалыПоСценариям[текущийСценарий] || 0) + 1;
      console.log('  ✗ [' + текущийСценарий + '] ' + что);
    } else {
      console.log('  ✓ [' + текущийСценарий + '] ' + что);
    }
  }
  return { сценарий, проверить, провалы, провалыПоСценариям, счёт: () => проверок };
}

/** Поддельные часы: время читается и двигается вручную. */
function поддельныеЧасы(стартМс) {
  let текущее = стартМс;
  const часы = function () { return текущее; };
  часы.сдвинуть = function (мс) { текущее += мс; };
  часы.установить = function (мс) { текущее = мс; };
  часы.сейчас = function () { return текущее; };
  return часы;
}

/* --- Весь набор сценариев 1-7, 10-14 (без диска, своя папка не нужна). --- */
function прогонВПамяти(создать, прогон) {
  const { сценарий, проверить } = прогон;
  const СТАРТ = Date.UTC(2026, 8, 23, 10, 0, 0); // 23.09.2026 10:00 — произвольная точка отсчёта

  /* 1. Три пульса подряд с шагом 60 с → одна сессия, минут = 2. */
  сценарий(1);
  {
    const часы = поддельныеЧасы(СТАРТ);
    const модуль = создать({ файл: 'без диска', часы: часы });
    проверить(модуль.учесть('900001', 'Аня', 'дурак', часы()) === true, 'первый пульс принят');
    часы.сдвинуть(МИНУТА);
    проверить(модуль.учесть('900001', 'Аня', 'дурак', часы()) === true, 'второй пульс принят');
    часы.сдвинуть(МИНУТА);
    проверить(модуль.учесть('900001', 'Аня', 'дурак', часы()) === true, 'третий пульс принят');

    const свод = модуль.сводка(часы());
    проверить(свод.сегодня.length === 1, 'в сводке за сегодня один человек');
    const аня = свод.сегодня[0] || {};
    проверить(аня.заходов === 1, 'три пульса подряд — один заход (было: ' + аня.заходов + ')');
    проверить(аня.минут === 2, 'зафиксированное правило: минут = 2, не 3 (было: ' + аня.минут + ')');
    проверить(аня.минутыПоИграм && аня.минутыПоИграм.дурак === 2, 'минутыПоИграм.дурак = 2 (было: ' + JSON.stringify(аня.минутыПоИграм) + ')');

    /* 2. Пауза 4 мин → новая сессия. */
    сценарий(2);
    часы.сдвинуть(4 * МИНУТА);
    проверить(модуль.учесть('900001', 'Аня', 'дурак', часы()) === true, 'пульс после паузы 4 мин принят');
    const свод2 = модуль.сводка(часы());
    const аня2 = свод2.сегодня[0] || {};
    проверить(аня2.заходов === 2, 'после паузы 4 мин — уже два захода за сегодня (было: ' + аня2.заходов + ')');
  }

  /* 3. Сессии старше 30 дней не попадают в сводку. */
  сценарий(3);
  {
    const часы = поддельныеЧасы(СТАРТ);
    const модуль = создать({ файл: 'без диска', часы: часы });
    // Старая сессия — 31 день назад от «сегодня».
    модуль.учесть('900002', 'Боря', 'шашки', часы());
    часы.установить(СТАРТ + 31 * 24 * 60 * МИНУТА);
    // Ещё один человек — чтобы сводка точно не была пустой по другой причине.
    модуль.учесть('900003', 'Вера', 'нарды', часы());
    const свод = модуль.сводка(часы());
    const номера = свод.неделя.map(function (ч) { return ч.номер; });
    проверить(номера.indexOf('900002') === -1, 'сессия 31-дневной давности не попала в сводку (неделя)');
    проверить(номера.indexOf('900003') !== -1, 'свежая сессия при этом на месте');
  }

  /* 4. Чужая игра отброшена. */
  сценарий(4);
  {
    const часы = поддельныеЧасы(СТАРТ);
    const модуль = создать({ файл: 'без диска', часы: часы });
    проверить(модуль.учесть('900004', 'Гена', 'футбол', часы()) === false, 'игра "футбол" отброшена');
    const свод = модуль.сводка(часы());
    проверить(свод.сегодня.length === 0, 'после отброшенного пульса сводка пуста');
  }

  /* 5. Номер принимается, только если он целиком из цифр. */
  сценарий(5);
  {
    const часы = поддельныеЧасы(СТАРТ);
    const модуль = создать({ файл: 'без диска', часы: часы });
    проверить(модуль.учесть('abc', 'Дима', 'шахматы', часы()) === false, 'номер "abc" без единой цифры отброшен');
    проверить(модуль.учесть('a9b0b0', 'Дима', 'шахматы', часы()) === false,
      'номер "a9b0b0" не целиком цифры — отброшен, а не обрезан до "900"');
    проверить(модуль.учесть('  900005  ', 'Женя', 'шахматы', часы()) === true,
      'номер с пробелами по краям — целиком цифры после trim — принят');
  }

  /* 6. Частый пульс (< 30 с) отброшен. */
  сценарий(6);
  {
    const часы = поддельныеЧасы(СТАРТ);
    const модуль = создать({ файл: 'без диска', часы: часы });
    модуль.учесть('900006', 'Егор', 'дурак', часы());
    часы.сдвинуть(10 * 1000); // 10 с — меньше порога в 30 с
    проверить(модуль.учесть('900006', 'Егор', 'дурак', часы()) === false, 'повтор через 10 с отброшен');
    const свод = модуль.сводка(часы());
    проверить(свод.сегодня[0].минут === 0, 'минуты не выросли от отброшенного пульса (было: ' + свод.сегодня[0].минут + ')');
  }

  /* 7. «Сейчас» пустеет через 3 мин тишины. */
  сценарий(7);
  {
    const часы = поддельныеЧасы(СТАРТ);
    const модуль = создать({ файл: 'без диска', часы: часы });
    модуль.учесть('900007', 'Жора', 'нарды', часы());
    проверить(модуль.сводка(часы()).сейчас.length === 1, 'сразу после пульса — в «сейчас»');
    часы.сдвинуть(2 * МИНУТА);
    проверить(модуль.сводка(часы()).сейчас.length === 1, 'через 2 мин тишины — ещё в «сейчас»');
    часы.сдвинуть(1 * МИНУТА + 1000); // итого 3:01 — за порогом
    проверить(модуль.сводка(часы()).сейчас.length === 0, 'через 3:01 тишины — «сейчас» пусто');
  }

  /* 10. Смена игры внутри одной сессии — минуты уходят по своим играм. */
  сценарий(10);
  {
    const часы = поддельныеЧасы(СТАРТ);
    const модуль = создать({ файл: 'без диска', часы: часы });
    модуль.учесть('900010', 'Коля', 'дурак', часы());   // сессия началась в «дураке»
    часы.сдвинуть(2 * МИНУТА);
    модуль.учесть('900010', 'Коля', 'шашки', часы());   // эти 2 мин человек ещё был в «дураке», игра меняется на «шашки»
    часы.сдвинуть(МИНУТА);
    модуль.учесть('900010', 'Коля', 'шашки', часы());   // эта минута уже в «шашках»

    const свод = модуль.сводка(часы());
    const коля = свод.сегодня[0] || {};
    проверить(коля.минутыПоИграм && коля.минутыПоИграм.дурак === 2,
      'минуты ДО смены игры (2) ушли прежней игре — дураку (было: ' + JSON.stringify(коля.минутыПоИграм) + ')');
    проверить(коля.минутыПоИграм && коля.минутыПоИграм.шашки === 1,
      'минута ПОСЛЕ смены игры (1) ушла новой игре — шашкам (было: ' + JSON.stringify(коля.минутыПоИграм) + ')');
  }

  /* 11. 201-я сессия одного номера за день отброшена. */
  сценарий(11);
  {
    const часы = поддельныеЧасы(СТАРТ);
    const модуль = создать({ файл: 'без диска', часы: часы });
    const ШАГ = 3 * МИНУТА + 1000; // чуть больше окна сессии — каждый пульс начинает новую сессию
    let принятых = 0;
    for (let i = 0; i < 200; i++) {
      if (i > 0) часы.сдвинуть(ШАГ);
      if (модуль.учесть('900011', 'Люда', 'дурак', часы())) принятых++;
    }
    проверить(принятых === 200, '200 сессий за день приняты (было: ' + принятых + ')');
    часы.сдвинуть(ШАГ);
    проверить(модуль.учесть('900011', 'Люда', 'дурак', часы()) === false, '201-я сессия за день отброшена');
  }

  /* 12. Управляющие знаки вырезаются из имени. */
  сценарий(12);
  {
    const часы = поддельныеЧасы(СТАРТ);
    const модуль = создать({ файл: 'без диска', часы: часы });
    модуль.учесть('900012', 'Миша\n\x00Вредный', 'дурак', часы());
    const свод = модуль.сводка(часы());
    const миша = свод.сегодня[0] || {};
    проверить(миша.имя === 'МишаВредный', 'управляющие знаки \\n и \\x00 вырезаны из имени (было: ' + JSON.stringify(миша.имя) + ')');
  }

  /* 13. Сдвиг часов назад: пульс отклонён, минуты не уходят в минус. */
  сценарий(13);
  {
    const часы = поддельныеЧасы(СТАРТ);
    const модуль = создать({ файл: 'без диска', часы: часы });
    модуль.учесть('900013', 'Оля', 'дурак', часы());
    часы.сдвинуть(МИНУТА);
    модуль.учесть('900013', 'Оля', 'дурак', часы());     // минут = 1
    часы.сдвинуть(-МИНУТА);                                // часы дёрнулись назад — как при сбое NTP
    проверить(модуль.учесть('900013', 'Оля', 'дурак', часы()) === false, 'пульс с более ранним временем отклонён');
    const свод = модуль.сводка(часы());
    const оля = свод.сегодня[0] || {};
    проверить(оля.минут >= 0, 'минуты не ушли в минус после отката часов (было: ' + оля.минут + ')');
    проверить(оля.минут === 1, 'минуты остались прежними — 1 (было: ' + оля.минут + ')');
  }

  /* 14. После прибраться() номер без сессий пропадает и из карты пульсов. */
  сценарий(14);
  {
    const часы = поддельныеЧасы(СТАРТ);
    const модуль = создать({ файл: 'без диска', часы: часы });
    модуль.учесть('900014', 'Ким', 'дурак', часы());
    проверить(модуль.размерПульсов() === 1, 'после пульса номер учтён в размерПульсов (было: ' + модуль.размерПульсов() + ')');
    часы.установить(СТАРТ + 31 * 24 * 60 * МИНУТА); // 31 день вперёд — старая сессия просрочена
    модуль.учесть('900015', 'Лена', 'дурак', часы()); // прибраться() вызывается внутри учесть()
    проверить(модуль.размерПульсов() === 1,
      'после прибраться() старый номер пропал из карты пульсов, остался только новый (было: ' + модуль.размерПульсов() + ')');
  }
}

/* 8-9: диск — своя временная папка, отдельно от прогона в памяти. */
function прогонНаДиске(создать, прогон) {
  const { сценарий, проверить } = прогон;
  const СТАРТ = Date.UTC(2026, 8, 23, 10, 0, 0);
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'посещения-'));
  const файл = path.join(папка, 'посещения.json');

  сценарий(8);
  {
    const часы = поддельныеЧасы(СТАРТ);
    const модуль1 = создать({ файл: файл, часы: часы });
    модуль1.учесть('900008', 'Зина', 'шахматы', часы());
    часы.сдвинуть(МИНУТА);
    модуль1.учесть('900008', 'Зина', 'шахматы', часы());
    модуль1.дописать();

    проверить(fs.existsSync(файл), 'файл на диске создан после дописать()');
    const наДиске = JSON.parse(fs.readFileSync(файл, 'utf8'));
    проверить(Array.isArray(наДиске.сессии) && наДиске.сессии.length === 1, 'на диске одна сессия');

    // Новый экземпляр модуля с тем же файлом — сессия должна быть на месте.
    const модуль2 = создать({ файл: файл, часы: часы });
    const свод = модуль2.сводка(часы());
    проверить(свод.сегодня.length === 1 && свод.сегодня[0].номер === '900008',
      'после нового создания модуля сессия Зины на месте');
    проверить(свод.сегодня[0].минут === 1, 'минуты пережили запись и чтение (было: ' + свод.сегодня[0].минут + ')');
  }

  сценарий(9);
  {
    fs.writeFileSync(файл, 'это не json, а мусор {{{', 'utf8');
    const часы = поддельныеЧасы(СТАРТ);
    let упало = false;
    let модуль3;
    try {
      модуль3 = создать({ файл: файл, часы: часы });
      модуль3.учесть('900009', 'Инна', 'дурак', часы());
      модуль3.сводка(часы());
    } catch (сбой) {
      упало = true;
    }
    проверить(упало === false, 'повреждённый файл не роняет модуль');
    проверить(модуль3 && модуль3.сводка(часы()).сегодня.length === 1, 'после порчи файла можно писать заново');
  }

  try { fs.rmSync(папка, { recursive: true, force: true }); } catch (сбой) { /* не страшно */ }
}

/**
 * Сделать копию server/посещения.js во временной папке с указанными
 * текстовыми заменами (одна прицельная поломка на вариант). Рядом
 * кладётся server/папка-данных.js — копия require'ит его же как соседа.
 */
function сделатьКопиюСЗаменами(замены, суффикс) {
  let текст = fs.readFileSync(ИСХОДНИК, 'utf8');
  for (const { откуда, куда } of замены) {
    const новыйТекст = текст.split(откуда).join(куда);
    if (новыйТекст === текст) {
      return { ошибка: 'поломка "' + суффикс + '" не применилась: не найден фрагмент ' + JSON.stringify(откуда.slice(0, 70)) + '…' };
    }
    текст = новыйТекст;
  }
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'посещения-сломать-' + суффикс + '-'));
  const файл = path.join(папка, 'посещения.js');
  fs.copyFileSync(path.join(КОРЕНЬ, 'server', 'папка-данных.js'), path.join(папка, 'папка-данных.js'));
  fs.writeFileSync(файл, текст, 'utf8');
  return { путь: файл };
}

