/**
 * Песочница: настоящие куски game.js и (по желанию) настоящий ярлык.js.
 * Настройки: ярлык (грузить ли файл), экран (какой виден), ссылка (что просит
 * ссылка), сеть (есть ли window.Сеть), рейтинг (работает ли счёт), статус
 * (ответ Telegram), сыграно (сколько партий уже в памяти).
 */
function собрать(настройки) {
  const н = Object.assign({
    ярлык: true, экран: 'экран-витрины', ссылка: '', сеть: true, рейтинг: true,
    статус: 'missed', сыграно: 3
  }, настройки || {});
  const м = { время: 1700000000000, окно: null, среда: null, вызовов: 0, спросили: 0, записанВРейтинг: 0, события: {} };
  const память = { home_shortcut: JSON.stringify({ played: н.сыграно, offers: 0, lastOffer: 0, added: false }) };
  const окно = {
    localStorage: {
      getItem: function (к) { return Object.prototype.hasOwnProperty.call(память, к) ? память[к] : null; },
      setItem: function (к, з) { память[к] = String(з); }
    },
    Telegram: {
      WebApp: {
        initData: 'x',
        isVersionAtLeast: function () { return true; },
        checkHomeScreenStatus: function (обратно) { м.спросили++; обратно(м.статус); },
        addToHomeScreen: function () { м.вызовов++; },
        onEvent: function (имя, обработчик) { м.события[имя] = обработчик; }
      }
    }
  };
  окно.window = окно;
  м.статус = н.статус;
  if (н.рейтинг) {
    окно.Рейтинг = {
      записатьПартию: function () { м.записанВРейтинг++; return Promise.resolve(null); },
      прочитать: function () { return {}; }
    };
  }
  if (н.сеть) {
    окно.Сеть = { какуюИгруПроситСсылка: function () { return м.ссылка; } };
  }
  м.ссылка = н.ссылка;
  м.экран = н.экран;
  const окружение = {
    window: окно,
    Date: { now: function () { return м.время; } },
    console: { log: function () {}, warn: function () {}, error: function () {} },
    Promise: Promise,
    document: { querySelector: function () { return м.экран ? { id: м.экран } : null; } },
    описаниеПартииДляСчёта: function () { return {}; },
    // Таблица ссылок ссылается на эти имена; нам важны только её ключи.
    СТРАНИЦА_ШАШЕК: 'шашки.html',
    СТРАНИЦА_ШАХМАТ: 'шахматы.html',
    СТРАНИЦА_НАРД: 'нарды.html',
    КЛЮЧ_ПОСЛЕДНЕЙ_ИГРЫ: 'last_game',
    ПОМЕТКА_ПРОШЛОЙ_ИГРЫ: 'вы играли',
    прочитатьНастройку: function () { return ''; },
    партияСДругомЖдёт: function () { return false; },
    написатьПометкуДурака: function () {},
    узнатьПроТурнирДляВитрины: function () {},
    освежитьКарточкуТурнира: function () {},
    написать: function () {},
    освежитьВкладкуПрофиля: function () {},
    эл: function () { return null; },
    освежитьСериюДней: function () {}
  };
  окружение.партия = null;
  vm.createContext(окружение);
  if (н.ярлык) vm.runInContext(ИСХОДНИК_ЯРЛЫКА, окружение, { filename: ФАЙЛ_ЯРЛЫКА });
  vm.runInContext([КУСОК_ТАБЛИЦЫ, КУСОК_ЭКРАНА, КУСОК_ПЕРЕБРОСКИ, КУСОК_ПРЕДЛОЖЕНИЯ,
    КУСОК_СЧЁТА, КУСОК_ПАРТИИ, КУСОК_ВИТРИНЫ].join('\n'), окружение, { filename: 'js/game.js (куски)' });
  м.окно = окно;
  м.среда = окружение;
  return м;
}

/** Закончить партию с таким результатом и позвать запись в счёт. */
function записать(м, партия) {
  vm.runInContext('партия = ' + JSON.stringify(партия) + ';', м.среда);
  vm.runInContext("записатьПартиюВСчёт('бот');", м.среда);
}

/** Вызвать настоящую освежитьВитрину в песочнице мира м. */
