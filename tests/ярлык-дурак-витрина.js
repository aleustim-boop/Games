/** Кусок исходника от начала «откуда» до первой строки «}» в начале строки. */
function вырезатьФункцию(откуда) {
  const начало = ИСХОДНИК_ИГРЫ.indexOf(откуда);
  if (начало === -1) return '';
  // Концы строк в файле могут быть и «\r\n», поэтому ищем регулярным выражением.
  const конец = /\r?\n\}\r?\n/g;
  конец.lastIndex = начало;
  const найдено = конец.exec(ИСХОДНИК_ИГРЫ);
  if (!найдено) return '';
  return ИСХОДНИК_ИГРЫ.slice(начало, найдено.index + найдено[0].indexOf('}') + 1);
}

/** Таблица «игра из ссылки → страница» целиком, как она записана в game.js. */
function вырезатьТаблицуСсылок() {
  const найдено = ИСХОДНИК_ИГРЫ.match(/const СТРАНИЦЫ_ИГР_ПО_ССЫЛКЕ = \{[\s\S]*?\};/);
  return найдено ? найдено[0] : '';
}

