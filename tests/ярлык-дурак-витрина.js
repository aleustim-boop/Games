console.log('\n6. index.html подключает js/ярлык.js до js/game.js');
{
  /** Позиция тега <script src="js/файл"> вне HTML-комментариев; -1 — нет. */
  const тег = function (исходник, файл) {
    // Комментарии заменяем пробелами той же длины: позиции остальных тегов не съезжают.
    const безКомментариев = исходник.replace(/<!--[\s\S]*?-->/g, function (с) { return ' '.repeat(с.length); });
    const найдено = безКомментариев.match(new RegExp('<script[^>]*src="js/' + файл.replace(/\./g, '\\.') + '(\\?[^"]*)?"'));
    return найдено ? найдено.index : -1;
  };
  // Сама проверка тега обязана уметь краснеть: закомментированный тег — это «нет».
  проверить(тег('<!-- <script src="js/ярлык.js"></script> -->', 'ярлык.js') === -1,
    'закомментированный тег <!-- <script src="js/ярлык.js"> --> за подключение не считается');
  проверить(тег('<script src="js/ярлык.js?v=1"></script>', 'ярлык.js') === 0, 'настоящий тег с ?v= находится');

  const ярлыкНомер = тег(ИСХОДНИК_СТРАНИЦЫ, 'ярлык.js');
  const играНомер = тег(ИСХОДНИК_СТРАНИЦЫ, 'game.js');
  проверить(ярлыкНомер !== -1, 'в index.html есть тег js/ярлык.js (не в комментарии)');
  проверить(играНомер !== -1, 'в index.html есть тег js/game.js');
  проверить(ярлыкНомер !== -1 && играНомер !== -1 && ярлыкНомер < играНомер, 'ярлык.js стоит раньше game.js');
}

