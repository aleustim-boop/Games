// Проверка Р12/Р20: серая строка «как ходить» над пультом «Захвата», чипы с «за», слова остатка.
// Запуск:  node tests/захват-как-ходить.js            — обычный прогон (без браузера)
//          node tests/захват-как-ходить.js --сломать  — портит КОПИИ стола и страницы во временной папке и требует провала
// Доводы для ломающих запусков: --файл <путь к столу>, --html <путь к странице>.
// Что держим: текст строки по фазам; строка скрыта в «Готово», раскрытии и конце; текст пишется только при смене;
// у #захват-как-ходить НЕТ aria-live (живой узел один — #захват-подсказка), иначе читалка зачитает всё дважды.
'use strict';
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const а = process.argv.slice(2);
const довод = (имя) => { const и = а.indexOf(имя); return и === -1 ? null : а[и + 1]; };
const путьСтола = довод('--файл') || path.join(КОРЕНЬ, 'js', 'захват-стол.js');
const путьСтраницы = довод('--html') || path.join(КОРЕНЬ, 'захват.html');

if (а.includes('--сломать')) {
  сломать();
} else {
  process.exit(прогон());
}

function прогон() {
  const Правила = require(path.join(КОРЕНЬ, 'js', 'захват-правила.js'));
  const Стол = require(путьСтола);
  const записи = {};   // id -> сколько раз писали textContent
  function сделатьУзел(id) {
    const классы = new Set();
    const х = { textContent: '', дети: [] };
    const у = new Proxy(х, {
      get(т, к) {
        if (к in т) return т[к];
        if (к === 'classList') return { add: (x) => классы.add(x), remove: (x) => классы.delete(x), contains: (x) => классы.has(x), toggle() {} };
        if (к === 'appendChild') return (д) => { т.дети.push(д); return д; };
        if (к === 'replaceChildren') return () => { т.дети.length = 0; };
        if (к === 'style') return { setProperty() {}, removeProperty() {}, getPropertyValue() { return ''; } };
        if (к === 'clientWidth' || к === 'offsetWidth') return 0;
        return function () { return null; };
      },
      set(т, к, з) { if (к === 'textContent' && id) записи[id] = (записи[id] || 0) + 1; т[к] = з; return true; }
    });
    у.__классы = классы;
    return у;
  }
  const узлы = {};
  const документ = {
    getElementById(id) { return узлы[id] || (узлы[id] = сделатьУзел(id)); },
    createElement() { return сделатьУзел(null); },
    defaultView: { getComputedStyle() { return { columnGap: '0px', getPropertyValue() { return ''; } }; } }
  };
  let провалов = 0, всего = 0;
  function проверка(название, условие, подробность) {
    всего++;
    if (!условие) { провалов++; console.log('ПРОВАЛ: ' + название + (подробность ? ' — ' + подробность : '')); }
  }

  const партия = Правила.новаяПартия({ игроки: ['a', 'b', 'c', 'd', 'e', 'f'], люди: ['a'] }, () => 0.5);
  const стол = Стол.создать({ документ: документ, рисункиЕсть: false, слушатели: {} });
  стол.начатьРаунд(партия, 'a', { готовы: null });
  const строка = () => документ.getElementById('захват-как-ходить');
  проверка('в расстановке — «Касание своей области — +1 войско»', строка().textContent === 'Касание своей области — +1 войско', строка().textContent);
  проверка('строка не скрыта в расстановке', !строка().__классы.has('скрыт'));
  const чипыНачала = документ.getElementById('захват-чипы').дети.map((ч) => ч.textContent);
  проверка('чипы есть (ноль найденного — провал)', чипыНачала.length > 0);
  проверка('в каждом чипе есть «за»', чипыНачала.every((т) => /^\+\d+ за /.test(т)), чипыНачала.join(' | '));

  const мои = партия.хозяева.map((х, н) => (х === 'a' && н > 0 ? н : 0)).filter(Boolean);
  проверка('есть свои области (ноль найденного — провал)', мои.length > 0);
  стол.поставитьВойска(мои[0], 1);
  проверка('после первого войска — «Долгое касание…»', строка().textContent === 'Долгое касание своей области — сразу несколько', строка().textContent);
  // Текст пишется только при смене: второе войско текст не меняет — запись в узел не должна повториться.
  const былоЗаписей = записи['захват-как-ходить'] || 0;
  проверка('запись в строку вообще шла (ноль найденного — провал)', былоЗаписей > 0, String(былоЗаписей));
  стол.поставитьВойска(мои[0], 1);
  проверка('текст не сменился — и не переписывается', (записи['захват-как-ходить'] || 0) === былоЗаписей,
    'было ' + былоЗаписей + ', стало ' + записи['захват-как-ходить']);
  const всегоВойск = Правила.подкрепление(партия, 'a').всего;
  стол.поставитьВойска(мои[0], всегоВойск - 2);
  проверка('всё поставлено, приказов нет — «Пальцем от своей области к соседней — удар»', строка().textContent === 'Пальцем от своей области к соседней — удар', строка().textContent);
  проверка('подсказка: «Войска стоят. Удар или «Готово»»', документ.getElementById('захват-подсказка').textContent === 'Войска стоят. Удар или «Готово»', документ.getElementById('захват-подсказка').textContent);
  стол.нажатьГотово();
  проверка('после «Готово» строка скрыта и пуста', строка().__классы.has('скрыт') && строка().textContent === '', строка().textContent);
  стол.изменить();
  проверка('после «Изменить» строка снова видна', !строка().__классы.has('скрыт') && строка().textContent !== '', строка().textContent);
  стол.задатьРаскрытие(true);
  проверка('в раскрытии строка скрыта и пуста', строка().__классы.has('скрыт') && строка().textContent === '', строка().textContent);
  стол.задатьРаскрытие(false);
  стол.задатьКонец(true);
  проверка('в конце партии строка скрыта', строка().__классы.has('скрыт') && строка().textContent === '', строка().textContent);
  проверка('пояснение остатка новое', Стол.СЛОВА_ОСТАТКА.пояснение === 'Войска ставятся касанием своей области. Остаток можно отправить в столицу одной кнопкой');

  // Страница: у строки нет aria-live, у подсказки — живой узел (role=status) один.
  const html = fs.readFileSync(путьСтраницы, 'utf8');
  const тегСтроки = (/<[^>]*id="захват-как-ходить"[^>]*>/.exec(html) || [''])[0];
  проверка('в захват.html нашёлся #захват-как-ходить (ноль найденного — провал)', тегСтроки !== '');
  проверка('у #захват-как-ходить нет aria-live', !/aria-live/i.test(тегСтроки), тегСтроки);
  проверка('у #захват-как-ходить нет role=status/alert/log', !/role="(status|alert|log)"/i.test(тегСтроки), тегСтроки);
  const тегПодсказки = (/<[^>]*id="захват-подсказка"[^>]*>/.exec(html) || [''])[0];
  проверка('#захват-подсказка остаётся живым узлом (role=status)', /role="status"/.test(тегПодсказки), тегПодсказки);

  console.log('Итого проверок: ' + всего + ', провалов: ' + провалов);
  return провалов ? 1 : 0;
}

function сломать() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-как-ходить-'));
  const стол = fs.readFileSync(path.join(КОРЕНЬ, 'js', 'захват-стол.js'), 'utf8');
  const страница = fs.readFileSync(path.join(КОРЕНЬ, 'захват.html'), 'utf8');
  const порчи = [
    ['стол', 'строка всегда первая', "return стоит ? 'Долгое касание своей области — сразу несколько' : 'Касание своей области — +1 войско';", "return 'Касание своей области — +1 войско';"],
    ['стол', 'строка не прячется в раскрытии', 'if (состояние.конец || состояние.раскрытие || состояние.готов || !вИгре()) return', 'if (состояние.конец || состояние.готов || !вИгре()) return'],
    ['стол', 'в чипе пропало «за»', "' за столицу'", "' столица'"],
    ['стол', 'текст пишется при каждом обновлении', 'if (строка.textContent !== текст) строка.textContent = текст;', 'строка.textContent = текст;'],
    ['стол', 'подсказка снова про «Стрелки»', 'Войска стоят. Удар или «Готово»', 'Войска стоят. Стрелки или «Готово»'],
    ['страница', 'у строки появился aria-live', 'id="захват-как-ходить"', 'id="захват-как-ходить" aria-live="polite"'],
    ['страница', 'у строки появился role=status', 'id="захват-как-ходить"', 'id="захват-как-ходить" role="status"']
  ];
  let красных = 0;
  порчи.forEach(function (п, н) {
    const текст = п[0] === 'стол' ? стол : страница;
    if (текст.split(п[2]).length !== 2) { console.log('ПРОВАЛ — место порчи не найдено ровно один раз: ' + п[1]); return; }
    const порченое = текст.replace(п[2], () => п[3]);
    // Порченый стол кладём в свою подпапку рядом с копиями соседей: стол их require'ит.
    const под = path.join(папка, 'п' + н);
    fs.mkdirSync(под);
    let путь;
    if (п[0] === 'стол') {
      for (const ф of ['захват-правила.js', 'захват-карта-вид.js', 'захват-карты.js']) fs.copyFileSync(path.join(КОРЕНЬ, 'js', ф), path.join(под, ф));
      путь = path.join(под, 'захват-стол.js');
    } else {
      путь = path.join(под, 'захват.html');
    }
    fs.writeFileSync(путь, порченое);
    const р = spawnSync(process.execPath, [__filename, п[0] === 'стол' ? '--файл' : '--html', путь], { encoding: 'utf8' });
    const красная = р.status === 1 && /ПРОВАЛ/.test(р.stdout);
    if (красная) красных++;
    console.log((красная ? 'КРАСНЕЕТ' : 'НЕ КРАСНЕЕТ (плохо)') + ' — ' + п[1] + ' (код ' + р.status + ')');
  });
  const чист = spawnSync(process.execPath, [__filename], { encoding: 'utf8' });
  console.log('Обычный прогон: код ' + чист.status + ' — ' + чист.stdout.trim().split('\n').pop());
  console.log('Красных: ' + красных + ' из ' + порчи.length);
  process.exit(красных === порчи.length && чист.status === 0 ? 0 : 1);
}
