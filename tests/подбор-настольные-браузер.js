function поднятьФайловыйСервер(корень, порт) {
  const сервер = spawn('node', [path.join(__dirname, 'локальный-сервер.js'), String(порт)], {
    env: Object.assign({}, process.env, { КОРЕНЬ_СЕРВЕРА: корень }),
    stdio: 'pipe'
  });
  return new Promise(function (готово, беда) {
    let вывод = '';
    const таймаут = setTimeout(function () { беда(new Error('Файловый сервер не поднялся за 5 секунд')); }, 5000);
    сервер.stdout.on('data', function (д) {
      вывод += д.toString();
      if (вывод.includes('запущен')) { clearTimeout(таймаут); готово(сервер); }
    });
    сервер.stderr.on('data', function (д) { console.log('  ошибка файлового сервера: ' + д.toString().trim()); });
    сервер.on('error', function (е) { clearTimeout(таймаут); беда(е); });
  });
}

/** Сервер комнат — модулем в этом же процессе. Возвращаем и подбор, и
    комнаты — сценарию с катаном нужен доступ к составу стола (людей и
    ботов с экрана надёжно не прочитать: карты ботов не выводятся числом). */
function поднятьСерверКомнат(корень, порт) {
  process.env.ДАННЫЕ_ИГРЫ = path.join(os.tmpdir(), 'подбор-настольные-браузер-' + process.pid);
  const сервера = require(path.join(корень, 'server', 'сервер.js'));
  const подбор = require(path.join(корень, 'server', 'подбор.js'));
  const комнаты = require(path.join(корень, 'server', 'комнаты.js'));
  сервера.оснасткаДляПроверки(ТОКЕН_ДЛЯ_ПРОБЫ, function () { return { ok: true }; });
  const сервер = сервера.создатьСервер();
  return new Promise(function (готово, беда) {
    сервер.once('error', беда);
    сервер.listen(порт, '127.0.0.1', function () { готово({ сервер: сервер, подбор: подбор, комнаты: комнаты }); });
  });
}

