async function новаяСтраница(браузер, настройкиПодделки) {
  const контекст = await браузер.newContext({ viewport: { width: 390, height: 844 } });
  const страница = await контекст.newPage();
  const ошибки = [];
  страница.on('pageerror', function (о) { ошибки.push('исключение: ' + о.message); });
  страница.on('console', function (с) {
    if (с.type() === 'error' && !/Failed to load resource/.test(с.text())) ошибки.push('консоль: ' + с.text());
  });
  await подготовитьПодделку(страница, настройкиПодделки);
  return { контекст: контекст, страница: страница, ошибки: ошибки };
}

async function нажать(страница, id) {
  return страница.evaluate(function (id) {
    const у = document.getElementById(id);
    if (!у) return false;
    у.click();
    return true;
  }, id);
}

async function видноЛи(страница, id) {
  return страница.evaluate(function (id) {
    const у = document.getElementById(id);
    return Boolean(у && !у.classList.contains('скрыт') && у.offsetParent !== null);
  }, id);
}

async function экранВиден(страница, id) {
  return страница.evaluate(function (id) {
    const у = document.getElementById(id);
    return Boolean(у && у.classList.contains('экран--виден'));
  }, id);
}

/** Состояние экрана ожидания подбора: узел не найден — честный провал,
    а не тихий пропуск (см. правило штаба «ноль найденного — это провал»). */
async function видЭкранаПодбора(страница) {
  return страница.evaluate(function () {
    const экран = document.getElementById('экран-подбор-соперника');
    if (!экран) return { экранВиден: false, непустой: false, ожиданиеТекст: '', отменаВидна: false };
    const ожидание = document.getElementById('подбор-ожидание');
    const отмена = document.getElementById('подбор-отмена');
    const видно = function (у) { return Boolean(у && !у.classList.contains('скрыт') && у.offsetParent !== null); };
    return {
      экранВиден: экран.classList.contains('экран--виден'),
      непустой: экран.children.length > 0,
      ожиданиеТекст: ожидание ? ожидание.textContent.trim() : '',
      отменаВидна: видно(отмена)
    };
  });
}

/** Дождаться, что экран сменился на #экран-игры и внутри виден узел,
    характерный именно для этой игры (карты деберца / рука домино /
    поле катана) — не пустой и правда на экране. Узел не найден вовсе —
    честный провал (waitForFunction ждёт условие Boolean(...), а не
    подставляет true молча). */
async function ждатьЭкранИгры(страница, признакСелектор, таймаутМс) {
  try {
    await страница.waitForFunction(function (селектор) {
      const активный = document.querySelector('.экран.экран--виден');
      if (!активный || активный.id !== 'экран-игры') return false;
      const узел = document.querySelector(селектор);
      return Boolean(узел && узел.children.length > 0 && узел.offsetParent !== null);
    }, признакСелектор, { timeout: таймаутМс || 8000 });
    return true;
  } catch (сбой) {
    return false;
  }
}

/** Код стола из localStorage (ключ «room_*», см. js/сеть.js, ЛАТИНСКОЕ_ИМЯ_ИГРЫ).
    Ключ ищем по началу имени, а не по точному имени игры — переименовали
    латинское имя игры, поиск не должен молча вернуть null. */
async function кодСохранённойКомнаты(страница) {
  return страница.evaluate(function () {
    try {
      const ключ = Object.keys(window.localStorage).find(function (к) { return к.indexOf('room_') === 0; });
      if (!ключ) return null;
      const запись = JSON.parse(window.localStorage.getItem(ключ) || '{}');
      return запись && запись.код ? String(запись.код) : null;
    } catch (сбой) {
      return null;
    }
  });
}

/** Код и пропуск из localStorage — нужны, чтобы через server/комнаты.js
    (общий кэш require с сервером комнат) заглянуть, кто на самом деле
    сидит за столом: люди или боты (с экрана это надёжно не прочитать). */
async function кодИПропускСохранённойКомнаты(страница) {
  return страница.evaluate(function () {
    try {
      const ключ = Object.keys(window.localStorage).find(function (к) { return к.indexOf('room_') === 0; });
      if (!ключ) return null;
      const запись = JSON.parse(window.localStorage.getItem(ключ) || '{}');
      if (!запись || !запись.код || !запись.пропуск) return null;
      return { код: String(запись.код), пропуск: String(запись.пропуск) };
    } catch (сбой) {
      return null;
    }
  });
}

/** Кто сидит за столом: число людей и ботов и сколько мест всего.
    Комната не нашлась — {людей:0, ботов:0, мест:0}: пусть проверки
    честно провалятся на нулях, а не молчат. */
function составСтола(комнаты, код, пропуск) {
  const найдено = код && пропуск ? комнаты.найтиИгрока(код, пропуск) : null;
  const комната = найдено ? найдено.комната : null;
  const сидят = комната ? Object.values(комната.игроки).filter(Boolean) : [];
  return {
    людей: сидят.filter(function (и) { return !и.этоБот; }).length,
    ботов: сидят.filter(function (и) { return и.этоБот; }).length,
    мест: комната ? комната.мест : 0,
    игра: комната ? комната.игра : null
  };
}

/* ---------------------------------------------------------------------
   Сценарий 1 и 2 (обобщённо). Двое жмут «Найти игру» в одной и той же
   настольной игре — сведены за один стол именно этой игры.
   --------------------------------------------------------------------- */
async function двоеЗаСтолом(браузер, название, страницаHtml, признакСелектор, номераИгроков, путьСнимка) {
  console.log('\n=== ' + название + ': двое жмут «Найти игру» — сведены за один стол ===');
  const а = await новаяСтраница(браузер, { подпись: initDataИгрока(номераИгроков[0], 'Первый' + название) });
  const б = await новаяСтраница(браузер, { подпись: initDataИгрока(номераИгроков[1], 'Второй' + название) });

  await а.страница.goto(АДРЕС_ФАЙЛОВ + страницаHtml + '?сервер=' + encodeURIComponent(АДРЕС_КОМНАТ));
  await б.страница.goto(АДРЕС_ФАЙЛОВ + страницаHtml + '?сервер=' + encodeURIComponent(АДРЕС_КОМНАТ));
  await а.страница.waitForTimeout(500);
  await б.страница.waitForTimeout(500);

  проверить(await нажать(а.страница, 'лобби-найти-игру'), название + ' (двое): у первого нашлась и нажалась карточка «Играть онлайн»');
  await а.страница.waitForTimeout(300);
  проверить(await видноЛи(а.страница, 'открытые-столы-подбор'), название + ' (двое): у первого кнопка «Найти игру» видна');
  проверить(await нажать(а.страница, 'открытые-столы-подбор'), название + ' (двое): первый нажал «Найти игру»');
  await а.страница.waitForTimeout(500);   // первый должен успеть встать в очередь раньше второго

  проверить(await нажать(б.страница, 'лобби-найти-игру'), название + ' (двое): у второго нашлась и нажалась карточка «Играть онлайн»');
  await б.страница.waitForTimeout(300);
  проверить(await нажать(б.страница, 'открытые-столы-подбор'), название + ' (двое): второй нажал «Найти игру»');

  const [видноА, видноБ] = await Promise.all([
    ждатьЭкранИгры(а.страница, признакСелектор, 10000),
    ждатьЭкранИгры(б.страница, признакСелектор, 10000)
  ]);
  проверить(видноА, название + ' (двое): у первого открылся стол его игры (узел «' + признакСелектор + '» виден и не пуст)');
  проверить(видноБ, название + ' (двое): у второго открылся стол его игры (узел «' + признакСелектор + '» виден и не пуст)');

  const кодА = await кодСохранённойКомнаты(а.страница);
  const кодБ = await кодСохранённойКомнаты(б.страница);
  проверить(Boolean(кодА) && кодА === кодБ, название + ' (двое): у обоих один и тот же код стола (вышло «' + кодА + '» и «' + кодБ + '»)');

  if (путьСнимка) {
    await б.страница.screenshot({ path: путьСнимка });
    console.log('  снимок: ' + путьСнимка);
  }

  проверить(а.ошибки.length === 0, название + ' (двое): у первого красных ошибок в консоли нет' + (а.ошибки.length ? ' — ' + а.ошибки.join(' | ') : ''));
  проверить(б.ошибки.length === 0, название + ' (двое): у второго красных ошибок в консоли нет' + (б.ошибки.length ? ' — ' + б.ошибки.join(' | ') : ''));

  await а.контекст.close();
  await б.контекст.close();
}

/* ---------------------------------------------------------------------
   Сценарий 3. Одиночка в деберце ждёт — сервер подсаживает бота.
   --------------------------------------------------------------------- */
async function одиночкаСБотом(браузер, подбор, путьСнимка) {
  console.log('\n=== Деберц: одиночка ждёт — сервер подсаживает бота ===');
  подбор.подменитьПорогОжиданияДляПроверки(300);   // порог до бота: 300 мс вместо 20 с
  try {
    const { контекст, страница, ошибки } = await новаяСтраница(браузер, { подпись: initDataИгрока(950101, 'Одиночка') });
    await страница.goto(АДРЕС_ФАЙЛОВ + 'деберц.html?сервер=' + encodeURIComponent(АДРЕС_КОМНАТ));
    await страница.waitForTimeout(500);

    проверить(await нажать(страница, 'лобби-найти-игру'), 'Деберц (одиночка): карточка «Играть онлайн» нашлась и нажалась');
    await страница.waitForTimeout(400);
    проверить(await нажать(страница, 'открытые-столы-подбор'), 'Деберц (одиночка): кнопка «Найти игру» нажалась');

    const виднаДоска = await ждатьЭкранИгры(страница, '#карты-человека', 15000);
    проверить(виднаДоска, 'Деберц (одиночка): дождалась бота — виден стол деберца (карты на руке)');

    if (путьСнимка) {
      await страница.screenshot({ path: путьСнимка });
      console.log('  снимок: ' + путьСнимка);
    }

    проверить(ошибки.length === 0, 'Деберц (одиночка): красных ошибок в консоли нет' + (ошибки.length ? ' — ' + ошибки.join(' | ') : ''));
    await контекст.close();
  } finally {
    подбор.подменитьПорогОжиданияДляПроверки();   // вернуть обычный порог
  }
}

