// Проверка этапа «Ночь-В»: мелочи вида. Работает по тексту файлов, без браузера.
// Запуск:            node tests/ночь-вид-мелочи.js
// Запуск с порчей:   node tests/ночь-вид-мелочи.js --порча
//   «порча» портит КОПИИ во временной папке и требует, чтобы каждая проверка покраснела.
const fs = require('fs');
const os = require('os');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ФАЙЛЫ = [
  'деберц.html', 'монополия.html', 'морской-бой.html', 'домино.html',
  'js/домино-экран.js', 'js/2048-ui.js', 'style-nonogram.css',
];

function читать(корень, имя) {
  return fs.readFileSync(path.join(корень, имя), 'utf8');
}

// Берёт кусок страницы от «<section id="…"» до следующего «<section»
function экранДомино(текст, id) {
  const начало = текст.indexOf('<section id="' + id + '"');
  if (начало < 0) return null; // не нашли экран — это провал, а не пропуск
  const конец = текст.indexOf('<section', начало + 10);
  return текст.slice(начало, конец < 0 ? undefined : конец);
}

// Возвращает список провалов вида {имя}; пустой список = всё хорошо
function проверитьВсё(корень) {
  const провалы = [];
  const требовать = (условие, имя) => { if (!условие) провалы.push(имя); };

  // 1. Строка листа «⋯» называется «Рекорды»
  const деберц = читать(корень, 'деберц.html');
  const деберцКнопка = деберц.match(/id="деберц-результаты"[^>]*>([^<]*)</);
  требовать(деберцКнопка && деберцКнопка[1].trim() === 'Рекорды', 'деберц: кнопка называется «Рекорды»');

  for (const файл of ['монополия.html', 'морской-бой.html']) {
    const строка = читать(корень, файл).match(/id="кнопка-лист-игры-рекорды"[^>]*>\s*([^<]*?)\s*</);
    требовать(строка && строка[1] === 'Рекорды', файл + ': строка листа называется «Рекорды»');
  }

  // 2. Домино: верхняя строка «‹ ⋯» на настройках и на экране друга
  const домино = читать(корень, 'домино.html');
  for (const id of ['дом-настройки', 'экран-друга']) {
    const экран = экранДомино(домино, id);
    требовать(экран !== null, 'домино: экран ' + id + ' найден');
    if (экран === null) continue;
    требовать(/class="верх-игры"/.test(экран), 'домино: на экране ' + id + ' есть общая верхняя строка «верх-игры»');
    требовать(/data-назад/.test(экран), 'домино: на экране ' + id + ' есть кнопка «‹» (data-назад)');
    требовать(/data-меню[^>]*aria-controls="лист-игры"/.test(экран), 'домино: на экране ' + id + ' есть «⋯» (data-меню), открывает лист-игры');
    требовать(!/дом-верх/.test(экран), 'домино: на экране ' + id + ' нет старой строки «дом-верх»');
  }
  const доминоЭкран = читать(корень, 'js/домино-экран.js');
  требовать(/querySelectorAll\('\[data-назад\]'\)/.test(доминоЭкран), 'домино-экран.js: «‹» подключена по data-назад');
  требовать(/querySelectorAll\('\[data-меню\]'\)/.test(доминоЭкран), 'домино-экран.js: «⋯» подключена по data-меню');

  // 3. 2048, окно итога: золотая (primary) кнопка одна — «Новая игра» при проигрыше
  const ui2048 = читать(корень, 'js/2048-ui.js');
  const итог = ui2048.match(/function showResult\(\)\{[\s\S]*?\n \}/);
  требовать(итог !== null, '2048: функция showResult найдена');
  if (итог) {
    const отмена = итог[0].split('\n').find(в => в.includes('Отменить последний ход'));
    требовать(Boolean(отмена) && /'secondary'/.test(отмена), '2048: «Отменить последний ход» — обычная кнопка (secondary), не золотая');
    const новая = итог[0].match(/\}else\{[\s\S]*?button\(body,'Новая игра'[^\n]*\n/);
    требовать(novaGold(новая), '2048: при проигрыше «Новая игра» — главная золотая');
  }

  // 4. Кроссворд, окно итога: шрифт обычной кнопки не мельче главной (16px)
  const css = читать(корень, 'style-nonogram.css');
  требовать(/dialog button\.secondary\s*\{[^}]*font-size:\s*16px/.test(css), 'кроссворд: в окне «Похвастаться» (secondary) шрифт 16px, как у главной');

  return провалы;
}

function novaGold(совпадение) {
  return совпадение !== null && !/'secondary'/.test(совпадение[0]);
}

function вывести(провалы) {
  if (провалы.length === 0) { console.log('Все проверки зелёные'); return; }
  for (const п of провалы) console.log('КРАСНО: ' + п);
}

// ---- Порча на копии -------------------------------------------------------
// Каждая порча: файл, что на что заменить, и часть имени провала, который обязан появиться
const ПОРЧИ = [
  { файл: 'деберц.html', от: '>Рекорды</button><button id="деберц-сдаться"', на: '>Мои результаты</button><button id="деберц-сдаться"', ждём: 'деберц: кнопка' },
  { файл: 'монополия.html', от: /(id="кнопка-лист-игры-рекорды"[^>]*>\s*)Рекорды/, на: '$1Мои результаты', ждём: 'монополия.html' },
  { файл: 'морской-бой.html', от: /(id="кнопка-лист-игры-рекорды"[^>]*>)Рекорды/, на: '$1Мои результаты', ждём: 'морской-бой.html' },
  { файл: 'домино.html', от: /(<section id="дом-настройки"[^>]*>)<div class="верх-игры">/, на: '$1<div class="дом-верх">', ждём: 'на экране дом-настройки есть общая' },
  { файл: 'домино.html', от: /(<section id="экран-друга"[^>]*>)<div class="верх-игры">/, на: '$1<div class="дом-верх">', ждём: 'экран-друга есть общая' },
  { файл: 'домино.html', от: '<section id="экран-друга"', на: '<section id="экран-друга-переименован"', ждём: 'экран экран-друга найден' },
  { файл: 'js/2048-ui.js', от: "undo();},'secondary');", на: 'undo();});', ждём: '«Отменить последний ход» — обычная' },
  { файл: 'style-nonogram.css', от: 'dialog button.secondary{font-size:16px}', на: 'dialog button.secondary{font-size:13px}', ждём: 'шрифт 16px' },
];

function порча() {
  let плохо = 0;
  const общая = fs.mkdtempSync(path.join(os.tmpdir(), 'ночь-вид-'));
  for (const п of ПОРЧИ) {
    // свежая копия всех файлов на каждую порчу — порчи не накладываются друг на друга
    const папка = fs.mkdtempSync(path.join(общая, 'копия-'));
    for (const ф of ФАЙЛЫ) {
      const куда = path.join(папка, ф);
      fs.mkdirSync(path.dirname(куда), { recursive: true });
      fs.copyFileSync(path.join(КОРЕНЬ, ф), куда);
    }
    const цель = path.join(папка, п.файл);
    const было = fs.readFileSync(цель, 'utf8');
    const стало = было.replace(п.от, п.на);
    if (стало === было) { console.log('НЕ ПОРТИТСЯ (узел не найден): ' + п.файл + ' ' + п.ждём); плохо++; continue; }
    fs.writeFileSync(цель, стало);
    const провалы = проверитьВсё(папка);
    const покраснело = провалы.some(в => в.includes(п.ждём));
    console.log((покраснело ? 'ок, покраснело: ' : 'НЕ ПОКРАСНЕЛО: ') + п.файл + ' → ' + п.ждём);
    if (!покраснело) плохо++;
  }
  console.log('Копии в: ' + общая);
  return плохо === 0 ? 0 : 1;
}

if (process.argv.includes('--порча')) {
  process.exit(порча());
} else {
  const провалы = проверитьВсё(КОРЕНЬ);
  вывести(провалы);
  process.exit(провалы.length === 0 ? 0 : 1);
}
