/* =====================================================================
   ОТЧЕГО В ПАРНОЙ ИГРЕ ПРИХОДИТСЯ СТОЯТЬ БЕЗ ДЕЛА.

   ЗАЧЕМ ЭТОТ ЗАМЕР. Владелец жаловался: «играем вчетвером, а по факту
   играют двое». Очередь починили — одиночка теперь отбивается 53.6%
   подходов вместо 75.3%. Но два числа при этом ВЫРОСЛИ: доля «стою
   без дела» поднялась с 24.8% до 27.5%, а «оба из пары простояли
   подход» — с 37.1% до 41.3%.

   Разработчик объяснил это так: в парной игре напарнику отбивающегося
   подкидывать НЕЛЬЗЯ (иначе пара топила бы сама себя), а за столом
   без пар такого запрета нет вовсе. Значит часть простоя — не недоделка,
   а само правило, и цель «довести до 23.6%, как без пар» недостижима.

   Догадка звучит убедительно, но это догадка. Здесь она проверяется
   числом: сколько простоя даёт ИМЕННО ЭТОТ ЗАПРЕТ, а сколько остаётся
   на всё прочее.

   ЧТО СЧИТАЕТСЯ ПРОСТОЕМ. Один «случай» — это один игрок в одном подходе.
   Игрок простоял подход, если игра ни разу не дала ему слова: не позвала
   ни нападать, ни отбиваться, ни подкидывать, ни говорить «пас».
   Считаем только тех, кто ещё в партии и с картами на руках: вышедшему
   стоять без дела не обидно.

   ПОЧЕМУ СЛОВО, А НЕ «СДЕЛАЛ ХОД». Слово — это когда игра спрашивает
   игрока (ктоХодит вернул его имя). Именно это человек и видит на экране
   как «мой черёд». Считать «сделал ход» было бы неверно: сказать «пас» —
   тоже участие, человек при этом нажимает кнопку.

   НА ЧТО ДЕЛИМ ПРОСТОЙ. Каждый простоявший попадает ровно в одну корзину:

     1. «запрет напарнику, а подкинуть БЫЛО ЧЕМ» — вот это и есть цена
        правила. Человек сидел с подходящей картой в руке, и ему не дали
        её положить, потому что отбивается его напарник.

     2. «запрет напарнику, но и подкинуть было нечем» — запрет тут ничего
        не отнял: подходящей карты у него всё равно не было. Эти случаи
        считать ценой правила нельзя, иначе цена выйдет завышенной.

     3. «нечем подкинуть» — подкидывать можно, но ни одна карта из руки
        не подходит по достоинству. Слова ему не дадут ни при каком
        правиле очереди.

     4. «круг не дошёл» — и можно, и есть чем, а подход кончился раньше,
        чем очередь добралась до него. ВОТ ЕДИНСТВЕННОЕ, что вообще можно
        было бы выправить работой над очередью.

   Корзины 1 и 2 отличаем от прочих не своим пересказом правила, а вопросом
   к самой игре: «подкидывающие» — её функция, и кого она в этот список
   не включила, тому подкидывать и не давали.

   «Было чем» смотрим не один раз, а на каждом шаге подхода: достоинства
   на столе за подход только прибавляются, и карта, негодная вначале,
   к концу подхода могла стать годной.

   КОНТРОЛЬ. Тот же замер за столом на четверых БЕЗ пар, где запрета
   не существует. Если корзины считаются верно, там корзины 1 и 2 обязаны
   быть пустыми.

   Запуск:
       node tests/сколько-простоя-от-запрета-напарнику.js
       node tests/сколько-простоя-от-запрета-напарнику.js 3000
   ===================================================================== */

const путь = require('path');
const игра = require(путь.join(__dirname, '..', 'js', 'game.js'));
const генератор = require(путь.join(__dirname, 'общий-генератор.js'));
генератор.захватитьСлучайность();

const ПАРТИЙ = Number(process.argv[2]) || 2000;
const ПРЕДЕЛ_ХОДОВ = 900;
const СМЕЩЕНИЕ = 100003;

const ЗАПРЕТ_СТОИЛ = 'запрет напарнику, было чем подкинуть';
const ЗАПРЕТ_ДАРОМ = 'запрет напарнику, но и нечем было';
const НЕЧЕМ = 'нечем подкинуть';
const НЕ_ДОШЛА_ОЧЕРЕДЬ = 'круг не дошёл';
const СТРАННОЕ = 'отбивался, а слова не дали';

function зерноПартии(н) { return (н * 7919 + СМЕЩЕНИЕ) | 0; }

/** Слепок стола — чтобы поймать ход, который ничего не изменил. */
function слепок(п) {
  const вРуках = п.игроки.map((и) => (п.руки[и] || []).length).join('/');
  const отбитых = п.стол.filter((пара) => пара.защита).length;
  return [игра.фаза(п), п.стол.length, отбитых, п.отбой.length, п.колода.length,
          вРуках, п.атакует, (п.пасы || []).join(',')].join('|');
}

function сыгратьИПосчитать(зерно, настройки, счёт) {
  генератор.поставитьЗерно(зерно);
  const п = игра.создатьПартию(настройки);

  let подходИдёт = false;
  let словоВПодходе = new Set();
  let защитникПодхода = null;
  let разрешалиПодкидывать = new Set();
  let былиВИгре = [];
  let картВРуке = {};
  let былоЧемПодкинуть = {};

  const закрытьПодход = function () {
    if (!подходИдёт) return;
    счёт.подходов++;
    let простояло = 0;
    let считанных = 0;
    for (const имя of былиВИгре) {
      if ((картВРуке[имя] || 0) === 0) continue;      // без карт стоять не обидно
      считанных++;
      if (словоВПодходе.has(имя)) continue;
      счёт.простоев++;
      простояло++;
      if (имя === защитникПодхода) { счёт.поКорзинам[СТРАННОЕ]++; continue; }
      if (!разрешалиПодкидывать.has(имя)) {
        счёт.поКорзинам[былоЧемПодкинуть[имя] ? ЗАПРЕТ_СТОИЛ : ЗАПРЕТ_ДАРОМ]++;
      } else if (!былоЧемПодкинуть[имя]) {
        счёт.поКорзинам[НЕЧЕМ]++;
      } else {
        счёт.поКорзинам[НЕ_ДОШЛА_ОЧЕРЕДЬ]++;
      }
    }
    счёт.случаев += считанных;
    if (простояло >= 2) счёт.подходовГдеПростоялиДвое++;
    подходИдёт = false;
    словоВПодходе = new Set();
  };

  let шагов = 0;
  while (!п.завершена && шагов++ < ПРЕДЕЛ_ХОДОВ) {
    const кто = игра.ктоХодит(п);
    if (кто === null) return false;

    if (п.стол.length === 0 && подходИдёт) закрытьПодход();

    if (п.стол.length > 0 && !подходИдёт) {
      подходИдёт = true;
      защитникПодхода = игра.защищается(п);
      разрешалиПодкидывать = new Set(игра.подкидывающие(п));
      былиВИгре = п.игроки.filter((и) => игра.вИгре(п, и));
      картВРуке = {};
      былоЧемПодкинуть = {};
      for (const имя of былиВИгре) картВРуке[имя] = (п.руки[имя] || []).length;
    }

    /* Пока подход идёт, на каждом шаге отмечаем, у кого появилась годная
       карта: достоинства на столе за подход только прибавляются. */
    if (подходИдёт) {
      const достоинства = игра.достоинстваНаСтоле(п);
      for (const имя of былиВИгре) {
        if (былоЧемПодкинуть[имя]) continue;
        былоЧемПодкинуть[имя] =
          (п.руки[имя] || []).some((к) => достоинства.indexOf(к.имя) !== -1);
      }
      словоВПодходе.add(кто);
    }

    const было = слепок(п);
    игра.ходБота(п, кто);
    if (слепок(п) === было) return false;      // ход ничего не изменил — партия встала
  }
  if (!п.завершена) return false;
  закрытьПодход();
  return true;
}

function пустойСчёт() {
  const поКорзинам = {};
  поКорзинам[ЗАПРЕТ_СТОИЛ] = 0;
  поКорзинам[ЗАПРЕТ_ДАРОМ] = 0;
  поКорзинам[НЕЧЕМ] = 0;
  поКорзинам[НЕ_ДОШЛА_ОЧЕРЕДЬ] = 0;
  поКорзинам[СТРАННОЕ] = 0;
  return { партий: 0, подходов: 0, случаев: 0, простоев: 0,
           подходовГдеПростоялиДвое: 0, поКорзинам: поКорзинам };
}

function замер(подпись, настройки) {
  const счёт = пустойСчёт();
  let недоиграно = 0;
  for (let н = 1; н <= ПАРТИЙ; н++) {
    if (сыгратьИПосчитать(зерноПартии(н), настройки, счёт)) счёт.партий++;
    else недоиграно++;
  }
  const доля = (ч) => счёт.случаев ? (ч / счёт.случаев * 100) : 0;
  console.log('--- ' + подпись + ' ---');
  console.log('  партий ' + счёт.партий + ', подходов ' + счёт.подходов +
    ', случаев «игрок в подходе» ' + счёт.случаев +
    (недоиграно ? '   !!! недоигранных партий: ' + недоиграно : ''));
  console.log('  ПРОСТОЙ ВСЕГО: ' + доля(счёт.простоев).toFixed(1) + '%  (' + счёт.простоев + ' случаев)');
  for (const корзина of Object.keys(счёт.поКорзинам)) {
    const ч = счёт.поКорзинам[корзина];
    if (ч === 0 && корзина === СТРАННОЕ) continue;
    console.log('      ' + (корзина + '                                        ').slice(0, 40) +
      доля(ч).toFixed(1) + '%  (' + ч + ')');
  }
  console.log('  подходов, где простояли двое и больше: ' +
    (счёт.подходов ? (счёт.подходовГдеПростоялиДвое / счёт.подходов * 100).toFixed(1) : '0') +
    '%  (' + счёт.подходовГдеПростоялиДвое + ' из ' + счёт.подходов + ')\n');
  return { счёт: счёт, доля: доля };
}

console.log('=== Отчего в парной игре стоят без дела ===');
console.log('партий на стол: ' + ПАРТИЙ + '; играют боты «обычный», колода 36\n');

const парами = замер('ЧЕТВЕРО ПАРАМИ (так играет владелец)',
  { сложность: 'обычный', игроков: 4, парами: true });
const безПар = замер('ЧЕТВЕРО БЕЗ ПАР (контроль: запрета напарнику не существует)',
  { сложность: 'обычный', игроков: 4, парами: false });

console.log('=== Проверка самого замера ===');
const ложныйЗапрет = безПар.счёт.поКорзинам[ЗАПРЕТ_СТОИЛ] + безПар.счёт.поКорзинам[ЗАПРЕТ_ДАРОМ];
const замерЧестный = ложныйЗапрет === 0;
console.log('  за столом без пар «запрет напарнику» встретился ' + ложныйЗапрет + ' раз ' +
  (замерЧестный ? '— как и должно быть, ни разу' : '— А ДОЛЖЕН НИ РАЗУ, корзины считаются неверно!'));
console.log('  странная корзина «отбивался, а слова не дали»: парами ' +
  парами.счёт.поКорзинам[СТРАННОЕ] + ', без пар ' + безПар.счёт.поКорзинам[СТРАННОЕ] +
  ' (обе обязаны быть пустыми)\n');

console.log('=== Что из этого следует ===');
const простойПарами = парами.доля(парами.счёт.простоев);
const простойБезПар = безПар.доля(безПар.счёт.простоев);
const разница = простойПарами - простойБезПар;
const ценаЗапрета = парами.доля(парами.счёт.поКорзинам[ЗАПРЕТ_СТОИЛ]);
const запретДаром = парами.доля(парами.счёт.поКорзинам[ЗАПРЕТ_ДАРОМ]);
const чинитсяОчередью = парами.доля(парами.счёт.поКорзинам[НЕ_ДОШЛА_ОЧЕРЕДЬ]);

console.log('  простой парами:  ' + простойПарами.toFixed(1) + '%');
console.log('  простой без пар: ' + простойБезПар.toFixed(1) + '%');
console.log('  разница между столами: ' + разница.toFixed(1) + ' пункта\n');
console.log('  ЦЕНА ЗАПРЕТА (сидел с годной картой, а положить не дали): ' + ценаЗапрета.toFixed(1) + '%');
console.log('  запрет впустую (всё равно нечем было):                    ' + запретДаром.toFixed(1) + '%');
console.log('  ОСТАЛОСЬ НА ОЧЕРЕДЬ (можно, есть чем, но круг не дошёл):  ' + чинитсяОчередью.toFixed(1) + '%');
console.log('    для сравнения без пар:                                  ' +
  безПар.доля(безПар.счёт.поКорзинам[НЕ_ДОШЛА_ОЧЕРЕДЬ]).toFixed(1) + '%\n');

if (!замерЧестный) {
  console.log('  Замер сам себе противоречит — выводы делать нельзя, сперва чинить замер.');
} else if (ценаЗапрета >= разница - 2) {
  console.log('  ДОГАДКА РАЗРАБОТЧИКА ПОДТВЕРЖДАЕТСЯ.');
  console.log('  Запрет подкидывать напарнику отбивающегося сам по себе отнимает у игроков');
  console.log('  ' + ценаЗапрета.toFixed(1) + '% подходов — этого с избытком хватает, чтобы объяснить всю разницу');
  console.log('  с непарным столом (' + разница.toFixed(1) + ' пункта). Это само правило игры, а не недоделка.');
  console.log('  Равняться на непарный стол НЕЛЬЗЯ: там такого правила нет вовсе,');
  console.log('  и цель «довести до уровня стола без пар» недостижима в принципе.');
} else {
  console.log('  ДОГАДКА ОБЪЯСНЯЕТ НЕ ВСЁ: запрет стоит ' + ценаЗапрета.toFixed(1) +
    '%, а разница со столом без пар ' + разница.toFixed(1) + ' пункта.');
  console.log('  Разбираться стоит с корзиной «круг не дошёл».');
}
console.log('');
if (чинитсяОчередью < 2) {
  console.log('  РАБОТОЙ НАД ОЧЕРЕДЬЮ можно отыграть не больше ' + чинитсяОчередью.toFixed(1) +
    '% — это всё, что осталось.');
  console.log('  Остальной простой держится правилами, а не порядком слова.');
} else {
  console.log('  Работой над очередью можно отыграть ещё ' + чинитсяОчередью.toFixed(1) + '% — это заметно.');
}
