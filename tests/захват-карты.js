function сумма(список) {
  return список.reduce(function (а, б) { return а + б; }, 0);
}

function проверитьСоседство(имя, карта, эталон) {
  const вычислено = Карты.соседство(карта);
  const номера = Object.keys(эталон);
  проверить(номера.length > 0, имя + ': эталон соседства не пустой (ноль найденного — провал)');
  проверить(Object.keys(вычислено).length === номера.length,
    имя + ': число областей в соседстве ' + Object.keys(вычислено).length + ', ждали ' + номера.length);
  номера.forEach(function (н) {
    проверить(JSON.stringify(вычислено[н]) === JSON.stringify(эталон[н]),
      имя + ': область ' + н + ' — из сетки ' + JSON.stringify(вычислено[н]) + ', в таблице ТЗ ' + JSON.stringify(эталон[н]));
    // Каждая пара — в обе стороны.
    (эталон[н] || []).forEach(function (д) {
      проверить((вычислено[д] || []).indexOf(Number(н)) !== -1,
        имя + ': пара ' + н + '–' + д + ' не видна с обратной стороны');
      проверить(Карты.соседние(карта, Number(н), д) && Карты.соседние(карта, д, Number(н)),
        имя + ': соседние(' + н + ', ' + д + ') не работает в обе стороны');
    });
  });
}

function проверитьУстройство(имя, карта, ждём) {
  проверить(!!карта, имя + ': карта найдена');
  if (!карта) return;
  const строки = карта.сетка;
  проверить(строки.length === ждём.рядов && карта.рядов === ждём.рядов, имя + ': рядов ' + строки.length + ', ждали ' + ждём.рядов);
  строки.forEach(function (с, р) {
    проверить(с.split(' ').length === ждём.столбцов, имя + ': в строке ' + р + ' не ' + ждём.столбцов + ' столбцов');
  });
  проверить(карта.области.length === ждём.областей, имя + ': областей ' + карта.области.length + ', ждали ' + ждём.областей);
  // Каждая буква области встречается в сетке; сот у каждой области хотя бы две (ТЗ рисует парами и больше).
  карта.области.forEach(function (о, и) {
    проверить(о.номер === и + 1, имя + ': номер области ' + о.номер + ' не по порядку');
    const сот = строки.join(' ').split(' ').filter(function (б) { return б === о.буква; }).length;
    проверить(сот >= ждём.минСот, имя + ': у области ' + о.номер + ' (' + о.буква + ') сот ' + сот + ', меньше ' + ждём.минСот);
    проверить(typeof о.имя === 'string' && о.имя.length > 0, имя + ': у области ' + о.номер + ' нет имени');
    проверить(typeof о.край === 'string', имя + ': область ' + о.номер + ' не входит ни в один край');
  });
  // Краёв столько, сколько ждали; каждая область ровно в одном крае.
  проверить(карта.края.length === ждём.краёв, имя + ': краёв ' + карта.края.length + ', ждали ' + ждём.краёв);
  const всеВКраях = [].concat.apply([], карта.края.map(function (к) { return к.области; }));
  проверить(всеВКраях.length === ждём.областей, имя + ': в краях ' + всеВКраях.length + ' мест, ждали ' + ждём.областей);
  проверить(new Set(всеВКраях).size === ждём.областей, имя + ': область встречается в двух краях');
  проверить(сумма(карта.края.map(function (к) { return к.прибавка; })) === ждём.суммаПрибавок,
    имя + ': сумма прибавок ' + сумма(карта.края.map(function (к) { return к.прибавка; })) + ', ждали ' + ждём.суммаПрибавок);
  карта.края.forEach(function (к, и) {
    проверить(к.прибавка === ждём.прибавки[и], имя + ': прибавка края «' + к.название + '» ' + к.прибавка + ', ждали ' + ждём.прибавки[и]);
    проверить(JSON.stringify(к.области) === JSON.stringify(ждём.краяОбласти[и]),
      имя + ': области края «' + к.название + '» не по ТЗ');
  });
}

function проверитьГнёзда(имя, карта, ждём) {
  const места = Object.keys(ждём);
  проверить(места.length > 0, имя + ': эталон гнёзд не пустой');
  проверить(Object.keys(карта.гнёзда).length === места.length, имя + ': число вариантов по местам не то');
  места.forEach(function (м) {
    const наборы = карта.гнёзда[м] || [];
    проверить(наборы.length === ждём[м].length, имя + ', мест ' + м + ': наборов ' + наборы.length + ', ждали ' + ждём[м].length);
    ждём[м].forEach(function (э, и) {
      проверить(!!наборы[и] && наборы[и].буквы.join('') === э.буквы && наборы[и].расстояние === э.расстояние,
        имя + ', мест ' + м + ': набор ' + э.буквы + ' (расстояние ' + э.расстояние + ') не по ТЗ');
      // Каждая буква гнезда — настоящая область карты.
      э.буквы.split('').forEach(function (б) {
        проверить(карта.области.some(function (о) { return о.буква === б; }), имя + ': в гнезде нет области ' + б);
      });
    });
  });
}

