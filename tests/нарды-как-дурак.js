'use strict';

/* Проверка без браузера: лобби и итог партии нард сделаны как у дурака
   (владелец 02.10, образец — шахматы, коммит 739e74b). Читает разметку и код
   как текст; слова о месте в рейтинге берёт из самого js/нарды-лобби.js.

   Запуск:  node tests/нарды-как-дурак.js [нарды.html] [нарды-экран.js] [нарды-лобби.js] [style-нарды.css]
   Пути нужны для «красного» запуска: проверка на КОПИЯХ, где поломку вернули,
   обязана упасть. Настоящие файлы портить нельзя.

   Ноль найденных узлов — провал, а не пропуск. */

const fs = require('fs');
const path = require('path');

const корень = path.join(__dirname, '..');
const путьHtml = process.argv[2] ? path.resolve(process.argv[2]) : path.join(корень, 'нарды.html');
const путьЭкрана = process.argv[3] ? path.resolve(process.argv[3]) : path.join(корень, 'js', 'нарды-экран.js');
const путьЛобби = process.argv[4] ? path.resolve(process.argv[4]) : path.join(корень, 'js', 'нарды-лобби.js');
const путьCss = process.argv[5] ? path.resolve(process.argv[5]) : path.join(корень, 'style-нарды.css');
const html = fs.readFileSync(путьHtml, 'utf8');
const экран = fs.readFileSync(путьЭкрана, 'utf8');
const лоббиКод = fs.readFileSync(путьЛобби, 'utf8');
const css = fs.readFileSync(путьCss, 'utf8');

let провалов = 0;
let всего = 0;
function проверить(условие, слова) {
  всего++;
  if (!условие) провалов++;
  console.log((условие ? '  ок      ' : '  ПРОВАЛ  ') + слова);
}

/** Кусок текста от начала до конца (включительно); пусто, если не нашли. */
function кусок(текст, начало, конец) {
  const от = текст.indexOf(начало);
  if (от === -1) return '';
  const до = текст.indexOf(конец, от);
  return до === -1 ? '' : текст.slice(от, до + конец.length);
}

console.log('Страница: ' + путьHtml);

console.log('\n1. Лобби: карточка профиля');
const лобби = кусок(html, '<section id="экран-лобби"', '</section>');
проверить(лобби.length > 0, 'экран «экран-лобби» найден');
проверить(/<span id="лобби-аватар" class="аватар"/.test(лобби), 'есть «лобби-аватар»');
проверить(/<span id="лобби-рейтинг" class="карточка-профиля__рейтинг карточка-профиля__рейтинг--нет"/.test(лобби),
  '«лобби-рейтинг» стоит с классом --нет (места пока нет)');
проверить(/<span id="лобби-место" class="карточка-профиля__место"><\/span>/.test(лобби), 'есть пустое «лобби-место»');
проверить(лобби.indexOf('Мой счёт') === -1, 'старой подписи «Мой счёт» нет');
проверить(/getElementById\('лобби-аватар'\)/.test(лоббиКод), 'код лобби ищет «лобби-аватар»');
проверить(/ЭкранРейтинга\.моёМесто\('нарды'\)/.test(лоббиКод), 'место берётся через ЭкранРейтинга.моёМесто(\'нарды\')');
проверить(/classList\.toggle\('карточка-профиля__рейтинг--нет'/.test(лоббиКод), 'класс --нет включается и снимается кодом');

console.log('\n2. Лобби: слова места (из самого файла)');
let слова = null;
try { слова = require(путьЛобби).словаМеста; } catch (ошибка) { слова = null; }
проверить(typeof слова === 'function', 'js/нарды-лобби.js отдаёт словаМеста наружу');
if (typeof слова === 'function') {
  проверить(слова({ место: 12, всего: 340 }) === '12-е место из 340', '«12-е место из 340»');
  проверить(слова({ место: 1 }) === '1-е место', 'без «всего» — «1-е место»');
  проверить(слова({}) === '' && слова(null) === '' && слова({ место: 0 }) === '', 'нет места — пустая строка');
} else {
  проверить(false, 'слова места не проверены: функции нет');
  проверить(false, 'слова места не проверены: функции нет');
  проверить(false, 'слова места не проверены: функции нет');
}

console.log('\n3. Лобби: картинка и входы');
const рамка = кусок(лобби, '<figure class="лобби__картинка">', '</figure>');
проверить(рамка.length > 0, 'рамка «лобби__картинка» найдена');
проверить(/<img class="лобби__рисунок"/.test(рамка), 'внутри рамки картинка «лобби__рисунок»');
проверить(/<figcaption class="лобби__подпись">[^<]*[А-Яа-я]{3,}[^<]*<\/figcaption>/.test(рамка), 'под картинкой подпись «лобби__подпись» по-русски');
const cssБезКомментариев = css.replace(/\/\*[\s\S]*?\*\//g, '');
проверить(css.length > 0 && !/\.лобби__картинка\s*\{[^}]*aspect-ratio/.test(cssБезКомментариев),
  'у нард нет своей пропорции рамки (берётся общая 16:10)');
проверить(/id="лобби-найти-игру"[\s\S]*?<span class="карточка-входа__название">Играть онлайн<\/span>/.test(лобби), 'вход «Играть онлайн»');
проверить(/id="лобби-боты"[\s\S]*?<span class="карточка-входа__название">Играть с ботами<\/span>/.test(лобби), 'вход «Играть с ботами»');

console.log('\n4. Итог партии: разметка');
const итог = кусок(html, '<section id="экран-итога"', '</section>');
проверить(итог.length > 0, 'плашка «экран-итога» найдена');
function кнопкаИтога(id, подпись) {
  const к = кусок(итог, '<button id="' + id + '"', '</button>');
  return к.length > 0 && к.indexOf('>' + подпись + '<') !== -1;
}
проверить(кнопкаИтога('кнопка-ещё', 'Играть ещё'), 'есть «Играть ещё»');
проверить(кнопкаИтога('кнопка-реванш', 'Реванш'), 'есть «Реванш»');
проверить(кнопкаИтога('кнопка-ещё-с-ботом', 'Сыграть с ботом'), 'есть «Сыграть с ботом»');
проверить(кнопкаИтога('кнопка-похвастаться', 'Похвастаться'), 'есть «Похвастаться»');
проверить(/id="кнопка-похвастаться"[^>]*кнопка--похвастаться/.test(итог), '«Похвастаться» с общим классом кнопка--похвастаться');
проверить(кнопкаИтога('кнопка-рекорды-итог', 'Рекорды'), 'есть «Рекорды»');
проверить(кнопкаИтога('кнопка-в-меню-итог', 'В меню'), 'есть «В меню»');
проверить(/<p id="итог-рейтинга"/.test(итог), 'есть место для «+N к рейтингу» (итог-рейтинга)');
проверить(!/style=/.test(итог), 'своего вида на плашке нет (style=)');
проверить(итог.indexOf('кнопка-другой-соперник') === -1, 'старой «Другая игра» (дубль «В меню») нет');
const порядок = ['кнопка-ещё"', 'кнопка-реванш"', 'кнопка-ещё-с-ботом"', 'кнопка-похвастаться"', 'кнопка-рекорды-итог"', 'кнопка-в-меню-итог"'];
const места = порядок.map(function (имя) { return итог.indexOf('id="' + имя); });
проверить(места.every(function (м) { return м !== -1; }) && места.every(function (м, и) { return и === 0 || м > места[и - 1]; }),
  'порядок кнопок как у дурака: ещё, реванш, с ботом, похвастаться, рекорды, в меню');

console.log('\n5. Итог партии: код');
проверить(/узел\('кнопка-в-меню-итог'\)\.addEventListener\('click', уйтиВМеню\)/.test(экран), '«В меню» привязана к уйтиВМеню');
проверить(/узел\('кнопка-ещё-с-ботом'\)\.addEventListener\('click', function \(\) \{ начатьПартию\('бот'\); \}\)/.test(экран), '«Сыграть с ботом» начинает партию с ботом');
проверить(/кнопкаСБотом\.classList\.toggle\('скрыт', !другУшёл\)/.test(экран), '«Сыграть с ботом» показывается, когда соперник ушёл');
проверить(/window\.Сеть\.похвастаться\(/.test(экран), '«Похвастаться» зовёт общую дверь Сеть.похвастаться');
проверить(/window\.Telegram\.WebApp\.initData/.test(экран), '«Похвастаться» только внутри Telegram');
проверить(/человекВыигралПартию\(\) && этоВнутриTelegram\(\)/.test(экран), '«Похвастаться» только после победы');
проверить(/ОчкиРейтинга\.словаИтога\(/.test(экран) && /узел\('итог-рейтинга'\)/.test(экран), 'строка рейтинга пишется через ОчкиРейтинга.словаИтога');
проверить(/узел\('кнопка-рекорды-итог'\)\.addEventListener/.test(экран) && /открытьСчёт\('нарды'\)/.test(экран), '«Рекорды» открывает личный счёт нард');

console.log('\n6. Подключения на странице');
проверить(/<script src="js\/очки-рейтинга\.js/.test(html), 'подключён js/очки-рейтинга.js');
проверить(/<script src="js\/похвастаться\.js/.test(html), 'подключён js/похвастаться.js');

console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
process.exit(провалов ? 1 : 0);
