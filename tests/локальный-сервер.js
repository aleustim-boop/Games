/* Простейший локальный сервер для ручной проверки игры в браузере.
   Нужен потому, что браузер-робот не открывает файлы по адресу file://.
   Запуск: node tests/локальный-сервер.js [порт]   (по умолчанию 8130)

   ПРО БЕЗОПАСНОСТЬ — читать обязательно, если будете это править.

   Сервер отдаёт файлы из папки проекта, а в папке проекта лежит bot/.env
   с настоящим токеном бота. Отсюда два правила, которые нельзя убирать:

   1. Слушаем только 127.0.0.1 — свой компьютер. Без второго довода у listen
      сервер слушает все сетевые карты, и тогда любой человек в той же
      Wi-Fi-сети может открыть http://адрес-этого-компьютера:порт/bot/.env
      и прочитать токен. README советует запускать этот сервер, то есть
      человек по инструкции сам себе открывал бы дверь.

   2. Папку bot и любые файлы, начинающиеся с точки (.env, .git, .claude),
      не отдаём вовсе. Проверка идёт ДО чтения с диска: секрет не должен
      попадать даже в память программы.

   Игре ничего из запрещённого не нужно: ей хватает index.html, style.css,
   js/ и tests/. */

'use strict';

const http = require('http');
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.resolve(path.join(__dirname, '..'));
const ПОРТ = Number(process.argv[2]) || 8130;
// Только свой компьютер. Менять на 0.0.0.0 или '' нельзя — см. пояснение выше.
const АДРЕС = '127.0.0.1';

const ТИПЫ = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8'
};

/** Убираем из адреса всё, чем можно вылезти за пределы папки проекта. */
function безопасныйПуть(адрес) {
  return path.normalize(адрес).replace(/^(\.\.[\\/])+/, '').replace(/^[\\/]+/, '');
}

/**
 * Можно ли отдавать этот адрес наружу.
 * Возвращает причину отказа или null, если всё в порядке.
 */
function причинаОтказа(адресДоРазбора, относительныйПуть) {
  // Смотрим и исходный адрес, и разобранный: так не поможет ни хитрая запись
  // адреса, ни разный регистр букв.
  const где = (адресДоРазбора + ' ' + относительныйПуть).toLowerCase();

  if (где.indexOf('.env') !== -1) {
    return 'в этом файле лежит токен бота, наружу он не отдаётся';
  }

  const части = относительныйПуть.split(/[\\/]/).filter(Boolean);
  if (части.length && части[0].toLowerCase() === 'bot') {
    return 'папка bot закрыта: в ней настройки бота';
  }
  for (const часть of части) {
    if (часть.charAt(0) === '.') {
      return 'служебные файлы и папки, начинающиеся с точки, наружу не отдаются';
    }
  }
  return null;
}

/** Точно ли файл лежит внутри папки проекта, а не где-то рядом. */
function внутриПроекта(файл) {
  const полный = path.resolve(файл);
  return полный === КОРЕНЬ || полный.startsWith(КОРЕНЬ + path.sep);
}

function отказать(ответ, код, текст) {
  ответ.writeHead(код, { 'Content-Type': 'text/plain; charset=utf-8' });
  ответ.end(текст);
}

http.createServer(function (запрос, ответ) {
  const сырой = запрос.url.split('?')[0];
  let адрес;
  try {
    адрес = decodeURIComponent(сырой);
  } catch (ошибка) {
    отказать(ответ, 400, 'непонятный адрес');
    return;
  }
  if (адрес === '/') адрес = '/index.html';

  const относительный = безопасныйПуть(адрес);

  // Сначала запреты — до всякого обращения к диску.
  const отказ = причинаОтказа(сырой + ' ' + адрес, относительный);
  if (отказ) {
    console.log('отказано: ' + адрес + ' — ' + отказ);
    отказать(ответ, 403, 'доступ закрыт: ' + отказ);
    return;
  }

  const файл = path.join(КОРЕНЬ, относительный);
  if (!внутриПроекта(файл)) {
    отказать(ответ, 403, 'доступ закрыт: файл вне папки проекта');
    return;
  }

  fs.readFile(файл, function (ошибка, данные) {
    if (ошибка) {
      отказать(ответ, 404, 'не найдено: ' + адрес);
      return;
    }
    ответ.writeHead(200, {
      'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'application/octet-stream',
      'Cache-Control': 'no-store'
    });
    ответ.end(данные);
  });
}).listen(ПОРТ, АДРЕС, function () {
  console.log('сервер запущен: http://' + АДРЕС + ':' + ПОРТ + '/index.html');
  console.log('слушает только этот компьютер; папка bot и файлы с точкой закрыты');
});
