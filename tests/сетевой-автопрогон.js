/**
 * РАЗВЕДКА ШАШЕК ПО СЕТИ.
 *
 * Партии в шашки этот прогон не играет — он про дурака. Но поля у шашек
 * свои, и список для них написан вручную; список, который никто ни разу
 * не сверил с живым сервером, — это выдумка, а не проверка. Поэтому здесь
 * мы заводим одну шашечную комнату, входим вторым игроком и пропускаем
 * оба вида через того же сыщика. Если сервер начнёт присылать шашкам
 * что-то новое — увидим это здесь, а не через месяц.
 */
async function разведкаШашек() {
  const создание = await запрос('/создать', { игра: 'шашки' });
  if (создание.номер !== 200 || !создание.данные.код) {
    console.log('шашки по сети: комнату завести не вышло (' + создание.номер + ') — разведку пропускаю');
    return;
  }
  осмотретьКонверт(создание.данные, 'шашки, создание');
  осмотреть(создание.данные.состояние, 'шашки, хозяин');

  const вход = await запрос('/войти', { код: создание.данные.код });
  проверить(вход.номер === 200 && вход.данные.пропуск, 'шашки: второй не смог войти по коду');
  осмотретьКонверт(вход.данные, 'шашки, вход');
  осмотреть(вход.данные.состояние, 'шашки, гость');

  const хозяин = await запрос('/состояние', { код: создание.данные.код, пропуск: создание.данные.пропуск });
  осмотретьКонверт(хозяин.данные, 'шашки, состояние хозяина');
  осмотреть(хозяин.данные.состояние, 'шашки, состояние хозяина');

  const вид = хозяин.данные.состояние || {};
  проверить(вид.игра === 'шашки', 'шашки: сервер помечает комнату игрой «шашки» (пришло «' + вид.игра + '»)');
  проверить(Array.isArray(вид.доска) && вид.доска.length === 8,
    'шашки: доска пришла восемью строками (пришло ' + (вид.доска && вид.доска.length) + ')');
  проверить(вид.мойЦвет === 'белые' || вид.мойЦвет === 'чёрные',
    'шашки: мой цвет назван словом («' + вид.мойЦвет + '»)');

  await запрос('/выйти', { код: создание.данные.код, пропуск: создание.данные.пропуск });
  await запрос('/выйти', { код: вход.данные.код, пропуск: вход.данные.пропуск });
  console.log('шашки по сети: комната заведена и осмотрена, полей в виде — ' + Object.keys(вид).length);
}

