/** Один POST-запрос. Возвращает { номер, данные } либо бросает понятную ошибку. */
function запрос(путь, тело, сколькоЖдатьМс) {
  return new Promise(function (готово, беда) {
    const текст = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const обращение = http.request({
      host: ХОСТ, port: ПОРТ, method: 'POST', path: encodeURI(путь),
      headers: { 'Content-Type': 'application/json', 'Content-Length': текст.length }
    }, function (ответ) {
      let куски = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (к) { куски += к; });
      ответ.on('end', function () {
        let данные = {};
        try { данные = JSON.parse(куски); } catch (сбой) { данные = { сыройОтвет: куски }; }
        готово({ номер: ответ.statusCode, данные: данные });
      });
    });
    обращение.setTimeout(сколькоЖдатьМс || 15000, function () {
      обращение.destroy(new Error('сервер не ответил на ' + путь + ' вовремя'));
    });
    обращение.on('error', беда);
    обращение.end(текст);
  });
}

function здоровье() {
  return new Promise(function (готово, беда) {
    // Русский адрес обязательно кодируем: без этого Node не соберёт запрос.
    http.get({ host: ХОСТ, port: ПОРТ, path: encodeURI('/здоровье') }, function (ответ) {
      let к = '';
      ответ.on('data', function (ч) { к += ч; });
      ответ.on('end', function () {
        try { готово(JSON.parse(к)); } catch (сбой) { беда(new Error('сервер ответил не JSON')); }
      });
    }).on('error', беда);
  });
}

