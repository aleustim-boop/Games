async function сыгратьКомнату(номер) {
  const создание = await запрос('/создать', {});
  осмотретьКонверт(создание.данные, 'комната ' + номер + ', создание');
  проверить(создание.номер === 200 && создание.данные.код,
    'комната ' + номер + ': сервер не создал игру');
  const первый = new Игрок('комната ' + номер + ', первый',
    создание.данные.код, создание.данные.пропуск, создание.данные.состояние);

  // Первый уже висит на длинном опросе — он должен получить новость о приходе друга
  const ожиданиеНовости = первый.чтоНового(создание.данные.состояние.версия, 20000);

  const вход = await запрос('/войти', { код: создание.данные.код });
  осмотретьКонверт(вход.данные, 'комната ' + номер + ', вход');
  проверить(вход.номер === 200 && вход.данные.пропуск,
    'комната ' + номер + ': друг не смог войти по коду');
  const второй = new Игрок('комната ' + номер + ', второй',
    вход.данные.код, вход.данные.пропуск, вход.данные.состояние);

  const новость = await ожиданиеНовости;
  проверить(новость.данные.изменилось === true,
    'комната ' + номер + ': длинный опрос не принёс новость о том, что друг вошёл');
  осмотретьКонверт(новость.данные, 'комната ' + номер + ', длинный опрос');
  осмотреть(новость.данные.состояние, 'комната ' + номер + ', длинный опрос');

  // Третий лишний: код закрыт
  const чужой = await запрос('/войти', { код: создание.данные.код });
  проверить(чужой.номер === 403,
    'комната ' + номер + ': в занятую комнату пустили третьего (' + чужой.номер + ')');

  await первый.обновить();
  await второй.обновить();

  let действий = 0;
  let сделаноЗаКруг = 1;
  while (!vidЗавершён(первый.вид) && действий < ПОТОЛОК_ДЕЙСТВИЙ && сделаноЗаКруг > 0) {
    сделаноЗаКруг = 0;

    // Ход за соперника не принимают никогда
    const непоправуХодит = первый.вид.яХожу ? второй : первый;
    const попытка = await непоправуХодит.ход({ действие: 'ходить', карта: 0 });
    проверить(!попытка.принято,
      'комната ' + номер + ': сервер принял ход не в свою очередь');

    for (const игрок of [первый, второй]) {
      await игрок.обновить();
      if (await походить(игрок)) сделаноЗаКруг++;
      действий++;
    }

    await первый.обновить();
    await второй.обновить();
    сверитьВиды(первый.вид, второй.вид, 'комната ' + номер + ', действие ' + действий);
  }

  проверить(действий < ПОТОЛОК_ДЕЙСТВИЙ,
    'комната ' + номер + ': партия не кончилась за ' + ПОТОЛОК_ДЕЙСТВИЙ + ' действий — похоже на зависание');
  проверить(vidЗавершён(первый.вид) && vidЗавершён(второй.вид),
    'комната ' + номер + ': партия кончилась не у обоих сразу');

  const итоги = [первый.вид.итог, второй.вид.итог].sort().join('+');
  проверить(итоги === 'победа+поражение' || итоги === 'ничья+ничья',
    'комната ' + номер + ': итоги не зеркальные — ' + итоги);

  // Реванш: зовут оба, карты раздаются заново
  const зов = await первый.ход({ действие: 'ещё' });
  проверить(зов.принято, 'комната ' + номер + ': первый не смог позвать на реванш');
  await второй.обновить();
  проверить(второй.вид.соперникХочетЕщё === true,
    'комната ' + номер + ': друг не увидел приглашения на реванш');
  const согласие = await второй.ход({ действие: 'ещё' });
  проверить(согласие.принято, 'комната ' + номер + ': второй не смог согласиться на реванш');
  await первый.обновить();
  проверить(первый.вид.завершена === false && первый.вид.мояРука.length === 6,
    'комната ' + номер + ': после реванша карты не роздали заново');

  await первый.выйти();
  await второй.выйти();

  return { действий: действий, итог: итоги };
}

/** Оба игрока обязаны видеть одинаковый стол, козырь и счёт карт. */
function сверитьВиды(а, б, где) {
  if (!а || !б) return;
  проверить(а.козырь === б.козырь, где + ': разный козырь');
  проверить(а.вКолоде === б.вКолоде, где + ': по-разному считают колоду');
  проверить(а.вОтбое === б.вОтбое, где + ': по-разному считают отбой');
  проверить(JSON.stringify(а.стол) === JSON.stringify(б.стол), где + ': разный стол');
  проверить(а.картУСоперника === б.мояРука.length,
    где + ': первый думает, что у друга ' + а.картУСоперника + ', а у того ' + б.мояРука.length);
  проверить(б.картУСоперника === а.мояРука.length,
    где + ': второй думает, что у друга ' + б.картУСоперника + ', а у того ' + а.мояРука.length);
  проверить(а.яХожу !== б.яХожу || а.завершена,
    где + ': сервер считает, что ходят оба сразу или никто');

  const моиКарты = new Set(а.мояРука.map(имяКарты));
  const общие = б.мояРука.map(имяКарты).filter(function (к) { return моиКарты.has(к); });
  проверить(общие.length === 0, где + ': одна и та же карта в обеих руках — ' + общие.join(','));

  const наСтоле = [];
  а.стол.forEach(function (п) {
    наСтоле.push(имяКарты(п.атака));
    if (п.защита) наСтоле.push(имяКарты(п.защита));
  });
  наСтоле.forEach(function (к) {
    проверить(!моиКарты.has(к), где + ': карта ' + к + ' лежит на столе и одновременно в руке');
  });
}

