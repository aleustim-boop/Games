'use strict';

/* =====================================================================
   Автопрогон игры вдвоём ПО НАСТОЯЩЕЙ СЕТИ.

   Чем отличается от server/проверка-двух-игроков.js: там правила и комнаты
   дёргают напрямую внутри одной программы. Здесь всё идёт так, как идёт
   у живых людей — обычными запросами по адресу http://127.0.0.1:ПОРТ,
   включая «длинный опрос», которым браузер узнаёт о ходе соперника.

   Что проверяется:
     1. Партия всегда доигрывается до конца и никогда не зависает.
     2. Оба игрока видят одно и то же: стол, козырь, сколько карт в колоде,
        сколько карт у соперника.
     3. Руки игроков нигде не пересекаются.
     4. Ни в одном ответе сервера нет чужих карт, карт колоды и карт отбоя.
     5. Длинный опрос действительно приносит новость о чужом ходе.
     6. Ход за соперника сервер не принимает никогда.
     7. После ухода обоих игроков комната пропадает — память не течёт.

   Запуск (сервер комнат должен быть уже поднят):
       node tests/сетевой-автопрогон.js               порт 8765, 8 комнат
       node tests/сетевой-автопрогон.js 8790 12       свой порт и число комнат
   ===================================================================== */

const http = require('http');

const ПОРТ = Number(process.argv[2]) || 8765;
const КОМНАТ = Number(process.argv[3]) || 8;
const ХОСТ = '127.0.0.1';

/* Больше этого числа действий одна партия длиться не может даже теоретически:
   36 карт, у каждой конечное число превращений. Упёрлись — значит зависли. */
const ПОТОЛОК_ДЕЙСТВИЙ = 800;

/* Поля, которые сервер имеет право прислать игроку. Всё остальное —
   утечка, даже если это выглядит безобидно. */
const РАЗРЕШЁННЫЕ_ПОЛЯ = new Set([
  'код', 'этап', 'версия', 'соперникПришёл', 'соперникНаСвязи', 'соперникУшёл',
  'событие', 'номерСобытия', 'сыграноПартий', 'яХочуЕщё', 'соперникХочетЕщё',
  'козырь', 'козырнаяКарта', 'вКолоде', 'вОтбое', 'мояРука', 'картУСоперника',
  'стол', 'фаза', 'яХожу', 'яАтакую', 'берут', 'завершена', 'итог',
  /* «видСобытия» — одно слово из закрытого словаря сервера («взял», «отбился»
     и подобные, см. «видСобытия» в server/партия-по-сети.js). Карт и имён
     в нём нет, поэтому поле разрешено. Внесено сюда после того, как замер
     объявил его утечкой: список полей отстал от сервера, а не сервер начал
     болтать лишнее. */
  'видСобытия'
]);

const провалы = [];
let проверок = 0;
let осмотреноОтветов = 0;

function проверить(условие, что) {
  проверок++;
  if (!условие) провалы.push(что);
}

/* ---------------------------------------------------------------------
   Разговор с сервером
   --------------------------------------------------------------------- */

/** Один POST-запрос. Возвращает { номер, данные } либо бросает понятную ошибку. */
function запрос(путь, тело, сколькоЖдатьМс) {
  return new Promise(function (готово, беда) {
    const текст = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const обращение = http.request({
      host: ХОСТ, port: ПОРТ, method: 'POST', path: encodeURI(путь),
      headers: { 'Content-Type': 'application/json', 'Content-Length': текст.length }
    }, function (ответ) {
      let куски = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (к) { куски += к; });
      ответ.on('end', function () {
        let данные = {};
        try { данные = JSON.parse(куски); } catch (сбой) { данные = { сыройОтвет: куски }; }
        готово({ номер: ответ.statusCode, данные: данные });
      });
    });
    обращение.setTimeout(сколькоЖдатьМс || 15000, function () {
      обращение.destroy(new Error('сервер не ответил на ' + путь + ' вовремя'));
    });
    обращение.on('error', беда);
    обращение.end(текст);
  });
}

function здоровье() {
  return new Promise(function (готово, беда) {
    // Русский адрес обязательно кодируем: без этого Node не соберёт запрос.
    http.get({ host: ХОСТ, port: ПОРТ, path: encodeURI('/здоровье') }, function (ответ) {
      let к = '';
      ответ.on('data', function (ч) { к += ч; });
      ответ.on('end', function () {
        try { готово(JSON.parse(к)); } catch (сбой) { беда(new Error('сервер ответил не JSON')); }
      });
    }).on('error', беда);
  });
}

/* ---------------------------------------------------------------------
   Сыщик: ищет чужие карты в том, что пришло игроку
   --------------------------------------------------------------------- */

/** Похоже ли это на карту. */
function этоКарта(что) {
  return что && typeof что === 'object' && что.масть !== undefined && что.имя !== undefined;
}

/**
 * Осмотреть состояние: нет ли в нём полей, которых там быть не должно,
 * и не лежит ли карта там, где полагается лежать только числу.
 */
function осмотреть(состояние, откуда) {
  if (!состояние) return;
  осмотреноОтветов++;

  Object.keys(состояние).forEach(function (поле) {
    проверить(РАЗРЕШЁННЫЕ_ПОЛЯ.has(поле),
      откуда + ': сервер прислал лишнее поле «' + поле + '»');
  });

  проверить(typeof состояние.картУСоперника === 'number',
    откуда + ': карты соперника пришли не числом');
  // Пока друг не пришёл, карт нет вовсе — счётчиков колоды и отбоя в ответе
  // просто не бывает, и это правильно. Спрашиваем их только за начатой партией.
  if (состояние.этап !== 'ожидание') {
    проверить(typeof состояние.вКолоде === 'number', откуда + ': колода пришла не числом');
    проверить(typeof состояние.вОтбое === 'number', откуда + ': отбой пришёл не числом');
    проверить(!(состояние.вКолоде === 0 && состояние.козырнаяКарта),
      откуда + ': колода пуста, а козырную карту всё ещё показывают');
  }

  // Ищем карты во всех углах ответа, кроме трёх законных мест
  (function обход(узел, путь) {
    if (!узел || typeof узел !== 'object') return;
    if (этоКарта(узел)) {
      проверить(/^(мояРука|стол|козырнаяКарта)/.test(путь),
        откуда + ': карта лежит там, где карт быть не должно — ' + путь);
      проверить(Object.keys(узел).length === 3,
        откуда + ': у карты появились лишние поля — ' + Object.keys(узел).join(','));
      return;
    }
    Object.keys(узел).forEach(function (к) {
      обход(узел[к], путь ? путь + '.' + к : к);
    });
  })(состояние, '');
}

/* ---------------------------------------------------------------------
   Один игрок
   --------------------------------------------------------------------- */

function имяКарты(к) { return к.имя + к.масть; }

class Игрок {
  constructor(имя, код, пропуск, состояние) {
    this.имя = имя;
    this.код = код;
    this.пропуск = пропуск;
    this.вид = состояние || null;
    if (состояние) осмотреть(состояние, имя);
  }

  async обновить() {
    const о = await запрос('/состояние', { код: this.код, пропуск: this.пропуск });
    проверить(о.номер === 200, this.имя + ': сервер не отдал состояние (' + о.номер + ')');
    this.вид = о.данные.состояние;
    осмотреть(this.вид, this.имя);
    return this.вид;
  }

  async ход(намерение) {
    const о = await запрос('/ход', Object.assign({ код: this.код, пропуск: this.пропуск }, намерение));
    проверить(о.номер === 200, this.имя + ': сервер ответил на ход кодом ' + о.номер);
    this.вид = о.данные.состояние;
    осмотреть(this.вид, this.имя);
    return о.данные;
  }

  /** Длинный опрос: ждём новостей не дольше указанного времени. */
  чтоНового(версия, сколькоЖдать) {
    return запрос('/что-нового', { код: this.код, пропуск: this.пропуск, версия: версия },
                  сколькоЖдать || 40000);
  }

  выйти() {
    return запрос('/выйти', { код: this.код, пропуск: this.пропуск });
  }
}

/* ---------------------------------------------------------------------
   Как играет наш «болван»: пробует всё подряд, пока не примут
   --------------------------------------------------------------------- */

/**
 * Сделать один осмысленный ход. Правил игрок не знает — он честно перебирает
 * свои карты, как это делает человек пальцем, и слушает отказы сервера.
 * Возвращает true, если сервер что-то принял.
 */
async function походить(игрок) {
  const вид = игрок.вид;
  if (!вид || vidЗавершён(вид)) return false;
  if (!вид.яХожу) return false;

  if (вид.фаза === 'защита') {
    for (let пара = 0; пара < вид.стол.length; пара++) {
      if (вид.стол[пара].защита) continue;
      for (let карта = 0; карта < вид.мояРука.length; карта++) {
        const ответ = await игрок.ход({ действие: 'отбить', пара: пара, карта: карта });
        if (ответ.принято) return true;
      }
    }
    const беру = await игрок.ход({ действие: 'беру' });
    проверить(беру.принято, игрок.имя + ': отбиться не смог и «Беру» тоже не приняли — ' + беру.причина);
    return беру.принято;
  }

  // Атака, подкидывание, докидывание
  for (let карта = 0; карта < вид.мояРука.length; карта++) {
    const ответ = await игрок.ход({ действие: 'ходить', карта: карта });
    if (ответ.принято) return true;
  }
  const бито = await игрок.ход({ действие: 'бито' });
  if (бито.принято) return true;

  проверить(false, игрок.имя + ': ходить нечем и подход не закрыть — «' + бито.причина +
                   '» (фаза ' + вид.фаза + ', карт в руке ' + вид.мояРука.length + ')');
  return false;
}

function vidЗавершён(вид) { return Boolean(вид && вид.завершена); }

/* ---------------------------------------------------------------------
   Одна комната от начала до конца
   --------------------------------------------------------------------- */

async function сыгратьКомнату(номер) {
  const создание = await запрос('/создать', {});
  проверить(создание.номер === 200 && создание.данные.код,
    'комната ' + номер + ': сервер не создал игру');
  const первый = new Игрок('комната ' + номер + ', первый',
    создание.данные.код, создание.данные.пропуск, создание.данные.состояние);

  // Первый уже висит на длинном опросе — он должен получить новость о приходе друга
  const ожиданиеНовости = первый.чтоНового(создание.данные.состояние.версия, 20000);

  const вход = await запрос('/войти', { код: создание.данные.код });
  проверить(вход.номер === 200 && вход.данные.пропуск,
    'комната ' + номер + ': друг не смог войти по коду');
  const второй = new Игрок('комната ' + номер + ', второй',
    вход.данные.код, вход.данные.пропуск, вход.данные.состояние);

  const новость = await ожиданиеНовости;
  проверить(новость.данные.изменилось === true,
    'комната ' + номер + ': длинный опрос не принёс новость о том, что друг вошёл');
  осмотреть(новость.данные.состояние, 'комната ' + номер + ', длинный опрос');

  // Третий лишний: код закрыт
  const чужой = await запрос('/войти', { код: создание.данные.код });
  проверить(чужой.номер === 403,
    'комната ' + номер + ': в занятую комнату пустили третьего (' + чужой.номер + ')');

  await первый.обновить();
  await второй.обновить();

  let действий = 0;
  let сделаноЗаКруг = 1;
  while (!vidЗавершён(первый.вид) && действий < ПОТОЛОК_ДЕЙСТВИЙ && сделаноЗаКруг > 0) {
    сделаноЗаКруг = 0;

    // Ход за соперника не принимают никогда
    const непоправуХодит = первый.вид.яХожу ? второй : первый;
    const попытка = await непоправуХодит.ход({ действие: 'ходить', карта: 0 });
    проверить(!попытка.принято,
      'комната ' + номер + ': сервер принял ход не в свою очередь');

    for (const игрок of [первый, второй]) {
      await игрок.обновить();
      if (await походить(игрок)) сделаноЗаКруг++;
      действий++;
    }

    await первый.обновить();
    await второй.обновить();
    сверитьВиды(первый.вид, второй.вид, 'комната ' + номер + ', действие ' + действий);
  }

  проверить(действий < ПОТОЛОК_ДЕЙСТВИЙ,
    'комната ' + номер + ': партия не кончилась за ' + ПОТОЛОК_ДЕЙСТВИЙ + ' действий — похоже на зависание');
  проверить(vidЗавершён(первый.вид) && vidЗавершён(второй.вид),
    'комната ' + номер + ': партия кончилась не у обоих сразу');

  const итоги = [первый.вид.итог, второй.вид.итог].sort().join('+');
  проверить(итоги === 'победа+поражение' || итоги === 'ничья+ничья',
    'комната ' + номер + ': итоги не зеркальные — ' + итоги);

  // Реванш: зовут оба, карты раздаются заново
  const зов = await первый.ход({ действие: 'ещё' });
  проверить(зов.принято, 'комната ' + номер + ': первый не смог позвать на реванш');
  await второй.обновить();
  проверить(второй.вид.соперникХочетЕщё === true,
    'комната ' + номер + ': друг не увидел приглашения на реванш');
  const согласие = await второй.ход({ действие: 'ещё' });
  проверить(согласие.принято, 'комната ' + номер + ': второй не смог согласиться на реванш');
  await первый.обновить();
  проверить(первый.вид.завершена === false && первый.вид.мояРука.length === 6,
    'комната ' + номер + ': после реванша карты не роздали заново');

  await первый.выйти();
  await второй.выйти();

  return { действий: действий, итог: итоги };
}

/** Оба игрока обязаны видеть одинаковый стол, козырь и счёт карт. */
function сверитьВиды(а, б, где) {
  if (!а || !б) return;
  проверить(а.козырь === б.козырь, где + ': разный козырь');
  проверить(а.вКолоде === б.вКолоде, где + ': по-разному считают колоду');
  проверить(а.вОтбое === б.вОтбое, где + ': по-разному считают отбой');
  проверить(JSON.stringify(а.стол) === JSON.stringify(б.стол), где + ': разный стол');
  проверить(а.картУСоперника === б.мояРука.length,
    где + ': первый думает, что у друга ' + а.картУСоперника + ', а у того ' + б.мояРука.length);
  проверить(б.картУСоперника === а.мояРука.length,
    где + ': второй думает, что у друга ' + б.картУСоперника + ', а у того ' + а.мояРука.length);
  проверить(а.яХожу !== б.яХожу || а.завершена,
    где + ': сервер считает, что ходят оба сразу или никто');

  const моиКарты = new Set(а.мояРука.map(имяКарты));
  const общие = б.мояРука.map(имяКарты).filter(function (к) { return моиКарты.has(к); });
  проверить(общие.length === 0, где + ': одна и та же карта в обеих руках — ' + общие.join(','));

  const наСтоле = [];
  а.стол.forEach(function (п) {
    наСтоле.push(имяКарты(п.атака));
    if (п.защита) наСтоле.push(имяКарты(п.защита));
  });
  наСтоле.forEach(function (к) {
    проверить(!моиКарты.has(к), где + ': карта ' + к + ' лежит на столе и одновременно в руке');
  });
}

/* ---------------------------------------------------------------------
   Запуск
   --------------------------------------------------------------------- */

async function главное() {
  console.log('=== Автопрогон игры вдвоём по настоящей сети ===');
  console.log('сервер: http://' + ХОСТ + ':' + ПОРТ + ', комнат за прогон: ' + КОМНАТ);

  let было;
  try {
    было = await здоровье();
  } catch (сбой) {
    console.error('Сервер комнат не отвечает на http://' + ХОСТ + ':' + ПОРТ + '/здоровье');
    console.error('Запустите его: node server/сервер.js ' + ПОРТ);
    process.exit(1);
  }
  console.log('сервер жив, комнат до прогона: ' + было.комнат);

  const начало = Date.now();
  const работа = [];
  for (let i = 1; i <= КОМНАТ; i++) работа.push(сыгратьКомнату(i));
  const результаты = await Promise.all(работа);
  const секунд = ((Date.now() - начало) / 1000).toFixed(1);

  const действий = результаты.reduce(function (с, р) { return с + р.действий; }, 0);
  console.log('сыграно партий: ' + результаты.length + ' (плюс столько же реваншей) за ' + секунд + ' с');
  console.log('действий всего: ' + действий);
  console.log('итоги: ' + результаты.map(function (р) { return р.итог; }).join(', '));

  // Комнаты после ухода обоих игроков жить не должны
  await new Promise(function (r) { setTimeout(r, 500); });
  const стало = await здоровье();
  проверить(стало.комнат <= было.комнат,
    'после прогона комнат стало больше: было ' + было.комнат + ', стало ' + стало.комнат);
  console.log('комнат после прогона: ' + стало.комнат);

  console.log('');
  console.log('проверок сделано: ' + проверок);
  console.log('ответов сервера осмотрено на чужие карты: ' + осмотреноОтветов);
  if (провалы.length === 0) {
    console.log('=== Итог: всё сошлось. Партии доигрываются, игроки видят одно и то же, ' +
                'чужих карт в ответах нет ===');
    return;
  }
  console.log('');
  console.log('!!! НАЙДЕНО ПЛОХОГО: ' + провалы.length);
  Array.from(new Set(провалы)).slice(0, 40).forEach(function (п) { console.log('  - ' + п); });
  process.exitCode = 1;
}

главное().catch(function (сбой) {
  console.error('Прогон сорвался:', сбой.message);
  process.exitCode = 1;
});
