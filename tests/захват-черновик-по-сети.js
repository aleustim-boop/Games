/**
 * POST на сервер проверки. «куски» — тело, разрезанное на части: каждая
 * уходит отдельной записью с паузой, так сервер получает их разными кусками.
 * Отдаёт { код, тело } (тело — разобранный JSON или null).
 */
function запрос(путь, тело, куски) {
  const части = куски || [Buffer.from(JSON.stringify(тело), 'utf8')];
  const длина = части.reduce(function (с, ч) { return с + ч.length; }, 0);
  return new Promise(function (готово, неудача) {
    let ответили = false;
    const з = http.request({
      host: '127.0.0.1', port: ПОРТ, path: encodeURI(путь), method: 'POST', agent: false,
      headers: { 'Content-Type': 'application/json', 'Content-Length': длина }
    }, function (ответ) {
      ответили = true;
      const принято = [];
      ответ.on('data', function (к) { принято.push(к); });
      ответ.on('end', function () {
        const текст = Buffer.concat(принято).toString('utf8');
        let разобрано = null;
        try { разобрано = JSON.parse(текст); } catch (сбой) { /* не JSON — оставим null */ }
        готово({ код: ответ.statusCode, тело: разобрано, сокет: з.socket });
      });
    });
    // Сервер ответил отказом раньше, чем дочитал тело, и закрыл связь — это не сбой проверки.
    з.on('error', function (сбой) { if (!ответили) неудача(сбой); });
    (async function () {
      for (let и = 0; и < части.length; и++) {
        if (и > 0) await пауза(120);
        if (и === части.length - 1) з.end(части[и]); else з.write(части[и]);
      }
    })();
  });
}

/** Длинный опрос: отдаёт { ответ: Promise, проснулся(), прервать() }. */
function начатьОпрос(тело) {
  let проснулся = false;
  let сокет = null;
  const ответ = new Promise(function (готово) {
    const текст = Buffer.from(JSON.stringify(тело), 'utf8');
    const з = http.request({
      host: '127.0.0.1', port: ПОРТ, path: encodeURI('/что-нового'), method: 'POST', agent: false,
      headers: { 'Content-Type': 'application/json', 'Content-Length': текст.length }
    }, function (о) {
      const принято = [];
      о.on('data', function (к) { принято.push(к); });
      о.on('end', function () {
        проснулся = true;
        let разобрано = null;
        try { разобрано = JSON.parse(Buffer.concat(принято).toString('utf8')); } catch (сбой) { /* null */ }
        готово(разобрано);
      });
    });
    з.on('socket', function (с) { сокет = с; });
    з.on('error', function () { готово(null); });
    з.end(текст);
  });
  return {
    ответ: ответ,
    проснулся: function () { return проснулся; },
    прервать: function () { if (сокет) сокет.destroy(); }
  };
}

