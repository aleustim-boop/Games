/** Копия server/ и js/ во временной папке с внесённой порчей; null — порчу не внести. */
function приготовитьКопию(родитель, номер) {
  const порча = ПОРЧИ[номер];
  const папка = fs.mkdtempSync(path.join(родитель, 'порча-' + номер + '-'));
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(папка, 'server'), {
    recursive: true,
    filter: function (откуда) {
      const имя = path.basename(откуда);
      return имя !== 'данные' && имя !== 'node_modules';
    }
  });
  fs.cpSync(path.join(КОРЕНЬ, 'js'), path.join(папка, 'js'), { recursive: true });
  const куда = path.join(папка, ФАЙЛ_ПОРЧ);
  let текст = fs.readFileSync(куда, 'utf8');
  for (const [было, стало] of порча.замены) {
    const нашлось = сколькоРаз(текст, было);
    if (нашлось !== 1) {
      console.log('  порчу №' + номер + ' не внести: кусок найден ' + нашлось + ' раз вместо одного: «' + было.slice(0, 80) + '»');
      return null;
    }
    текст = текст.split(какВФайле(текст, было)).join(какВФайле(текст, стало));
  }
  fs.writeFileSync(куда, текст);
  return папка;
}

function ломающийПрогон(толькоНомер) {
  const номера = толькоНомер ? [толькоНомер] : Object.keys(ПОРЧИ);
  for (const н of номера) {
    if (!ПОРЧИ[н]) {
      console.log('Нет порчи №' + н + ', номера: ' + Object.keys(ПОРЧИ).join(', '));
      console.log('Итого порч: 0, не пойманных: 1');
      process.exit(1);
    }
  }
  const родитель = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-черновик-сеть-лом-'));
  console.log('=== Ломающий прогон «Маршрут тихой двери»: копии в ' + родитель + ' ===\n');
  let непойманных = 0;
  for (const н of номера) {
    const порча = ПОРЧИ[н];
    const копия = приготовитьКопию(родитель, н);
    if (!копия) {
      непойманных++;
      console.log('  ✗ порча №' + н + ' (' + порча.что + '): место не найдено — проверка устарела');
      continue;
    }
    const прогон = spawnSync(process.execPath, [__filename, '--папка', копия], {
      encoding: 'utf8', timeout: 120000, env: Object.assign({}, process.env, { OPEN_HIDDEN_GAMES: 'захват' })
    });
    const вывод = (прогон.stdout || '') + (прогон.stderr || '');
    const красные = вывод.split('\n').filter(function (с) { return с.indexOf('✗ ПРОВАЛ: ') !== -1; });
    const своя = красные.find(function (с) { return с.indexOf('✗ ПРОВАЛ: ' + порча.ждём) !== -1; });
    const поймана = прогон.status === 1 && Boolean(своя);
    if (!поймана) непойманных++;
    console.log((поймана ? '  ✓' : '  ✗ НЕ ПОЙМАНА:') + ' порча №' + н + ' (' + порча.что + '), ждём ' + порча.ждём +
      ', код ' + прогон.status + ', красных ' + красные.length +
      (своя ? ' — ' + своя.trim().slice(0, 150) : (красные[0] ? ' — первая: ' + красные[0].trim().slice(0, 150) : '')));
    try { fs.rmSync(копия, { recursive: true, force: true }); } catch (уборка) { /* временная папка, не страшно */ }
  }
  try { fs.rmSync(родитель, { recursive: true, force: true }); } catch (уборка) { /* не страшно */ }
  console.log('\nИтого порч: ' + номера.length + ', не пойманных: ' + непойманных);
  process.exit(непойманных ? 1 : 0);
}

