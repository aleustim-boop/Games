/** Первая своя область места (номера областей — с 1). */
function своёПоле(п, ключ) {
  return п.хозяева.findIndex((х, н) => н > 0 && х === ключ);
}

/** Своя область и всё подкрепление на неё — черновик, который точно примут. */
function черновикНаВсё(п, ключ) {
  return { раунд: п.раунд, расстановка: { [своёПоле(п, ключ)]: п.подкрепление[ключ] }, приказы: [] };
}

/** К черновику «основа» — ещё один приказ на одно войско, который правила примут. */
function сНовымПриказом(п, ключ, основа) {
  const всего = п.хозяева.length - 1;
  for (let из = 1; из <= всего; из++) {
    if (п.хозяева[из] !== ключ) continue;
    for (let в = 1; в <= всего; в++) {
      if (в === из) continue;
      const черновик = {
        раунд: п.раунд,
        расстановка: Object.assign({}, основа.расстановка || {}),
        приказы: (основа.приказы || []).concat([{ из: из, в: в, сколько: 1 }])
      };
      if (Правила.проверитьЧерновик(п, ключ, черновик).принято) return черновик;
    }
  }
  throw new Error('не нашлось ни одного приказа, который правила примут');
}

/** Черновик без номера раунда и лишних полей — так его хранит партия. */
function какХранится(черновик) {
  return JSON.stringify({
    расстановка: черновик.расстановка || {},
    приказы: (черновик.приказы || []).map(пр => ({ из: пр.из, в: пр.в, сколько: пр.сколько }))
  });
}

/**
 * Самый большой допустимый по устройству черновик: карта «материк» (6 мест),
 * все области свои, приказ по каждой паре соседей, числа 4-значные.
 * Строится из той же карты, что у правил.
 */
function худшийЧерновик(раунд) {
  const карта = Карты.КАРТЫ.материк;
  const соседи = Карты.соседство(карта);
  const расстановка = {};
  const приказы = [];
  карта.области.forEach(function (о) {
    расстановка[о.номер] = 9999;
    (соседи[о.номер] || []).forEach(function (с) { приказы.push({ из: о.номер, в: с, сколько: 9999 }); });
  });
  return { раунд: раунд, расстановка: расстановка, приказы: приказы };
}

function байт(тело) { return Buffer.byteLength(JSON.stringify(тело), 'utf8'); }

async function сервержив(метка, стол) {
  const о = await запрос('/состояние', { код: стол.код, пропуск: стол.пропуска.Аня });
  проверить(о.код === 200 && Boolean(о.тело && о.тело.состояние), метка + ' сервер жив: /состояние отвечает ' + о.код);
}

/** Сценарий: упал — это провал его пункта, а не тишина. */
async function сценарий(название, дело) {
  console.log('\n' + название);
  try {
    await дело();
  } catch (сбой) {
    const пункт = название.slice(0, название.indexOf(')') + 1);
    проверить(false, пункт + ' сценарий оборвался: ' + (сбой && сбой.stack || сбой));
  }
}

