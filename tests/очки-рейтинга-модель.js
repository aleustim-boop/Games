/** Дать отработать цепочке fetch → json → then. */
function дождаться() {
  return new Promise(function (готово) { setImmediate(готово); });
}

/* Адрес, который отдаёт поддельная дверь window.Сеть.адрес() в обычных
   сценариях — сам по себе не важен, важно только что он идёт ОТТУДА. */
const АДРЕС_СЕТИ = 'https://пример.trycloudflare.com';

/**
 * Поднять общее/js/очки-рейтинга.js в песочнице с поддельным fetch и, по
 * умолчанию, поддельной дверью window.Сеть.адрес() — как на настоящей
 * странице, где общее/js/сеть.js уже подключена и подключена раньше этого файла.
 * настройки: { telegram: boolean, безСети: boolean,
 *              отвечает(путь, тело) → данные|null|'обрыв' }
 */
function поднятьОчки(исходник, настройки) {
  const н = настройки || {};
  const запросы = [];
  function поддельныйFetch(адрес, опции) {
    let тело = {};
    try { тело = JSON.parse((опции && опции.body) || '{}'); } catch (сбой) { тело = {}; }
    const путь = String(адрес).replace(/^https?:\/\/[^/]+/, '');
    запросы.push({ путь: путь, тело: тело });
    const ответ = н.отвечает ? н.отвечает(путь, тело) : {};
    if (ответ === 'обрыв') return Promise.reject(new Error('сеть недоступна'));
    return Promise.resolve({ ok: true, status: 200, json: function () { return Promise.resolve(ответ || {}); } });
  }
  const стр = поднять(исходник, {
    fetch: поддельныйFetch,
    имяФайла: 'общее/js/очки-рейтинга.js',
    telegram: н.telegram === false ? { initData: '' } : { initData: ПОДПИСЬ }
  });
  // window — общий объект между песочницей и этим кодом (передан по ссылке
  // в vm.createContext), поэтому дописать её сюда можно и ПОСЛЕ загрузки
  // модуля: адресСервера() читает window.Сеть заново при каждом вызове.
  if (!н.безСети) {
    стр.окно.Сеть = { адрес: function () { return АДРЕС_СЕТИ; } };
  }
  return {
    окно: стр.окно,
    запросы: запросы,
    считать: function (путь) { return запросы.filter(function (з) { return з.путь === путь; }).length; }
  };
}

async function проверитьМодуль(исходник) {
  проверить(typeof исходник === 'string' && исходник.length > 0, '0: исходник прочитан');

  // 1–2: обычный путь — билет пришёл, сдача ушла с тем же билетом.
  const стр = поднятьОчки(исходник, {
    отвечает: function (путь) {
      if (путь === '/билет') return { ок: true, билет: 'билет-АБВ', партияНеКорочеСекунд: 40, причина: '' };
      if (путь === '/итог-с-ботом') return { ок: true, очков: 2, причина: '' };
      return {};
    }
  });
  const ручка = стр.окно.ОчкиРейтинга.взятьБилет('шашки', 'лёгкий');
  await дождаться();
  проверить(стр.считать('/билет') === 1, '1: старт партии — ровно один запрос на /билет (получили: ' + стр.считать('/билет') + ')');
  const запросБилета = стр.запросы.filter(function (з) { return з.путь === '/билет'; })[0];
  проверить(Boolean(запросБилета) && запросБилета.тело.initData === ПОДПИСЬ &&
    запросБилета.тело.игра === 'шашки' && запросБилета.тело.уровень === 'лёгкий',
    '1б: в запросе билета — подпись, игра и уровень (получили: ' + JSON.stringify(запросБилета && запросБилета.тело) + ')');

  const итог = await стр.окно.ОчкиРейтинга.сдать(ручка, 'победа');
  проверить(стр.считать('/итог-с-ботом') === 1, '2: итог партии — ровно один запрос на /итог-с-ботом (получили: ' + стр.считать('/итог-с-ботом') + ')');
  const запросСдачи = стр.запросы.filter(function (з) { return з.путь === '/итог-с-ботом'; })[0];
  проверить(Boolean(запросСдачи) && запросСдачи.тело.билет === 'билет-АБВ' && запросСдачи.тело.исход === 'победа',
    '2б: в сдаче — тот же билет, что пришёл на шаге 1, и верный исход (получили: ' + JSON.stringify(запросСдачи && запросСдачи.тело) + ')');
  проверить(итог && итог.ок === true && итог.очков === 2, '2в: «сдать» вернула ответ сервера (получили: ' + JSON.stringify(итог) + ')');

  // 3: сервер не выдал билет — сдача в сеть не уходит.
  const безБилета = поднятьОчки(исходник, {
    отвечает: function (путь) {
      if (путь === '/билет') return { ок: false, билет: '', причина: 'игра без бота' };
      return {};
    }
  });
  const ручкаБезБилета = безБилета.окно.ОчкиРейтинга.взятьБилет('монополия', 'обычный');
  await дождаться();
  const итогБезБилета = await безБилета.окно.ОчкиРейтинга.сдать(ручкаБезБилета, 'поражение');
  проверить(безБилета.считать('/итог-с-ботом') === 0, '3: без билета сдача в сеть не уходит (запросов: ' + безБилета.считать('/итог-с-ботом') + ')');
  проверить(itogОкЛожь(итогБезБилета), '3б: «сдать» без билета отвечает тихим отказом (получили: ' + JSON.stringify(итогБезБилета) + ')');

  // 4: сдать дважды подряд, не дожидаясь первого ответа, — уходит один раз.
  const дважды = поднятьОчки(исходник, {
    отвечает: function (путь) {
      if (путь === '/билет') return { ок: true, билет: 'билет-2', партияНеКорочеСекунд: 40, причина: '' };
      if (путь === '/итог-с-ботом') return { ок: true, очков: 1, причина: '' };
      return {};
    }
  });
  const ручкаДважды = дважды.окно.ОчкиРейтинга.взятьБилет('нарды', 'сложный');
  await дождаться();
  const оба = await Promise.all([
    дважды.окно.ОчкиРейтинга.сдать(ручкаДважды, 'победа'),
    дважды.окно.ОчкиРейтинга.сдать(ручкаДважды, 'победа')
  ]);
  проверить(дважды.считать('/итог-с-ботом') === 1, '4: двойная сдача одной ручки — уходит только один запрос (получили: ' + дважды.считать('/итог-с-ботом') + ')');
  проверить(оба[0].ок === true && оба[1].ок === false, '4б: первая сдача успешна, вторая — тихий отказ (получили: ' + JSON.stringify(оба) + ')');

  // 5: fetch падает — исключение наружу не вылетает.
  const падает = поднятьОчки(исходник, { отвечает: function () { return 'обрыв'; } });
  let ошибкаВзятьБилет = null;
  let ручкаПадает;
  try {
    ручкаПадает = падает.окно.ОчкиРейтинга.взятьБилет('шашки', 'лёгкий');
    await дождаться();
  } catch (сбой) { ошибкаВзятьБилет = сбой; }
  проверить(ошибкаВзятьБилет === null, '5: «взятьБилет» не бросает исключение при обрыве fetch (получили: ' + ошибкаВзятьБилет + ')');
  let ошибкаСдать = null;
  let итогПадает;
  try {
    итогПадает = await падает.окно.ОчкиРейтинга.сдать(ручкаПадает, 'ничья');
  } catch (сбой) { ошибкаСдать = сбой; }
  проверить(ошибкаСдать === null, '5б: «сдать» не бросает исключение при обрыве fetch (получили: ' + ошибкаСдать + ')');
  проверить(itogОкЛожь(итогПадает), '5в: «сдать» при обрыве fetch отвечает тихим отказом (получили: ' + JSON.stringify(итогПадает) + ')');

  // 6: без подписи Telegram — ноль запросов вообще.
  const безПодписи = поднятьОчки(исходник, { telegram: false, отвечает: function () { return { ок: true, билет: 'x', причина: '' }; } });
  const ручкаБезПодписи = безПодписи.окно.ОчкиРейтинга.взятьБилет('шашки', 'лёгкий');
  await дождаться();
  const итогБезПодписи = await безПодписи.окно.ОчкиРейтинга.сдать(ручкаБезПодписи, 'победа');
  проверить(безПодписи.запросы.length === 0, '6: без подписи Telegram — ноль запросов (получили: ' + безПодписи.запросы.length + ')');
  проверить(itogОкЛожь(итогБезПодписи), '6б: без подписи Telegram «сдать» отвечает тихим отказом');

  // 7: window.Сеть на странице нет (общее/js/сеть.js не подключена) — ноль
  // запросов вообще, даже с подписью Telegram: своего адреса не строим.
  const безСети = поднятьОчки(исходник, {
    безСети: true,
    отвечает: function () { return { ок: true, билет: 'x', партияНеКорочеСекунд: 40, причина: '' }; }
  });
  проверить(безСети.окно.Сеть === undefined, '7 (условие): в песочнице правда нет window.Сеть');
  const ручкаБезСети = безСети.окно.ОчкиРейтинга.взятьБилет('шашки', 'лёгкий');
  await дождаться();
  const итогБезСети = await безСети.окно.ОчкиРейтинга.сдать(ручкаБезСети, 'победа');
  проверить(безСети.запросы.length === 0, '7: без window.Сеть — ноль запросов (получили: ' + безСети.запросы.length + ')');
  проверить(itogОкЛожь(итогБезСети), '7б: без window.Сеть «сдать» отвечает тихим отказом (получили: ' + JSON.stringify(итогБезСети) + ')');

  /* -----------------------------------------------------------------
     8–14: та же дверь для рейтинга по лучшему счёту (Э4.4):
     взятьБилетСчёта → /билет-счёта, сдатьСчёт → /счёт.
     ----------------------------------------------------------------- */

  // 8: старт партии-головоломки — запрос на /билет-счёта с игрой и режимом.
  const стрСчёт = поднятьОчки(исходник, {
    отвечает: function (путь) {
      if (путь === '/билет-счёта') return { ок: true, билет: 'билет-счёта-1', зерно: 12345, причина: '' };
      if (путь === '/счёт') return { ок: true, улучшение: true, значение: 4096, причина: '' };
      return {};
    }
  });
  const ручкаСчёт = стрСчёт.окно.ОчкиРейтинга.взятьБилетСчёта('2048', 'classic');
  await дождаться();
  проверить(стрСчёт.считать('/билет-счёта') === 1, '8: старт партии-головоломки — ровно один запрос на /билет-счёта (получили: ' + стрСчёт.считать('/билет-счёта') + ')');
  const запросБилетаСчёта = стрСчёт.запросы.filter(function (з) { return з.путь === '/билет-счёта'; })[0];
  проверить(Boolean(запросБилетаСчёта) && запросБилетаСчёта.тело.initData === ПОДПИСЬ &&
    запросБилетаСчёта.тело.игра === '2048' && запросБилетаСчёта.тело.режим === 'classic',
    '8б: в запросе билета-счёта — подпись, игра и режим (получили: ' + JSON.stringify(запросБилетаСчёта && запросБилетаСчёта.тело) + ')');

  // 9: итог мерой «очки» — /счёт с тем же билетом и полем «счёт», без «секунд».
  const итогОчки = await стрСчёт.окно.ОчкиРейтинга.сдатьСчёт(ручкаСчёт, { счёт: 4096 });
  проверить(стрСчёт.считать('/счёт') === 1, '9: итог партии-головоломки — ровно один запрос на /счёт (получили: ' + стрСчёт.считать('/счёт') + ')');
  const запросСчёта = стрСчёт.запросы.filter(function (з) { return з.путь === '/счёт'; })[0];
  проверить(Boolean(запросСчёта) && запросСчёта.тело.билет === 'билет-счёта-1' && запросСчёта.тело.счёт === 4096 &&
    !Object.prototype.hasOwnProperty.call(запросСчёта.тело, 'секунд'),
    '9б: в сдаче счёта — тот же билет, поле «счёт», без «секунд» (получили: ' + JSON.stringify(запросСчёта && запросСчёта.тело) + ')');
  // 10: ответ сервера { улучшение, значение } доходит до вызывающего кода.
  проверить(итогОчки && итогОчки.ок === true && итогОчки.улучшение === true && итогОчки.значение === 4096,
    '10: «сдатьСчёт» вернула ответ сервера целиком (получили: ' + JSON.stringify(итогОчки) + ')');

  // 9б: итог мерой «время» — /счёт полем «секунд», без «счёт».
  const стрВремя = поднятьОчки(исходник, {
    отвечает: function (путь) {
      if (путь === '/билет-счёта') return { ок: true, билет: 'билет-счёта-время', зерно: 1, причина: '' };
      if (путь === '/счёт') return { ок: true, улучшение: false, значение: 812, причина: '' };
      return {};
    }
  });
  const ручкаВремя = стрВремя.окно.ОчкиРейтинга.взятьБилетСчёта('судоку', 'эксперт');
  await дождаться();
  await стрВремя.окно.ОчкиРейтинга.сдатьСчёт(ручкаВремя, { секунд: 812 });
  const запросВремени = стрВремя.запросы.filter(function (з) { return з.путь === '/счёт'; })[0];
  проверить(Boolean(запросВремени) && запросВремени.тело.секунд === 812 &&
    !Object.prototype.hasOwnProperty.call(запросВремени.тело, 'счёт'),
    '9в: мера «время» — в сдаче поле «секунд», без «счёт» (получили: ' + JSON.stringify(запросВремени && запросВремени.тело) + ')');

  // 11: билет не пришёл (сервер отказал) — сдатьСчёт в сеть не уходит.
  const счётБезБилета = поднятьОчки(исходник, {
    отвечает: function (путь) {
      if (путь === '/билет-счёта') return { ок: false, билет: '', причина: 'У этой игры нет рейтинга по лучшему счёту' };
      return {};
    }
  });
  const ручкаСчётБезБилета = счётБезБилета.окно.ОчкиРейтинга.взятьБилетСчёта('нарды', 'сложный');
  await дождаться();
  const итогСчётБезБилета = await счётБезБилета.окно.ОчкиРейтинга.сдатьСчёт(ручкаСчётБезБилета, { счёт: 10 });
  проверить(счётБезБилета.считать('/счёт') === 0, '11: без билета-счёта сдача в сеть не уходит (запросов: ' + счётБезБилета.считать('/счёт') + ')');
  проверить(itogСчётаОкЛожь(итогСчётБезБилета), '11б: «сдатьСчёт» без билета отвечает тихим отказом (получили: ' + JSON.stringify(итогСчётБезБилета) + ')');

  // 12: сдать дважды подряд, не дожидаясь первого ответа, — уходит один раз.
  const счётДважды = поднятьОчки(исходник, {
    отвечает: function (путь) {
      if (путь === '/билет-счёта') return { ок: true, билет: 'билет-счёта-2', зерно: 2, причина: '' };
      if (путь === '/счёт') return { ок: true, улучшение: true, значение: 100, причина: '' };
      return {};
    }
  });
  const ручкаСчётДважды = счётДважды.окно.ОчкиРейтинга.взятьБилетСчёта('блоки', 'classic');
  await дождаться();
  const обаСчёт = await Promise.all([
    счётДважды.окно.ОчкиРейтинга.сдатьСчёт(ручкаСчётДважды, { счёт: 100 }),
    счётДважды.окно.ОчкиРейтинга.сдатьСчёт(ручкаСчётДважды, { счёт: 100 })
  ]);
  проверить(счётДважды.считать('/счёт') === 1, '12: двойная сдача одной ручки — уходит только один запрос (получили: ' + счётДважды.считать('/счёт') + ')');
  проверить(обаСчёт[0].ок === true && обаСчёт[1].ок === false, '12б: первая сдача успешна, вторая — тихий отказ (получили: ' + JSON.stringify(обаСчёт) + ')');

  // 13: fetch падает (500/обрыв) — исключение наружу не вылетает.
  const счётПадает = поднятьОчки(исходник, { отвечает: function () { return 'обрыв'; } });
  let ошибкаВзятьБилетСчёта = null;
  let ручкаСчётПадает;
  try {
    ручкаСчётПадает = счётПадает.окно.ОчкиРейтинга.взятьБилетСчёта('змейка', 'classic');
    await дождаться();
  } catch (сбой) { ошибкаВзятьБилетСчёта = сбой; }
  проверить(ошибкаВзятьБилетСчёта === null, '13: «взятьБилетСчёта» не бросает исключение при обрыве fetch (получили: ' + ошибкаВзятьБилетСчёта + ')');
  let ошибкаСдатьСчёт = null;
  let итогСчётПадает;
  try {
    итогСчётПадает = await счётПадает.окно.ОчкиРейтинга.сдатьСчёт(ручкаСчётПадает, { счёт: 5 });
  } catch (сбой) { ошибкаСдатьСчёт = сбой; }
  проверить(ошибкаСдатьСчёт === null, '13б: «сдатьСчёт» не бросает исключение при обрыве fetch (получили: ' + ошибкаСдатьСчёт + ')');
  проверить(itogСчётаОкЛожь(итогСчётПадает), '13в: «сдатьСчёт» при обрыве fetch отвечает тихим отказом (получили: ' + JSON.stringify(итогСчётПадает) + ')');

  // 14: без подписи Telegram и без window.Сеть — ноль запросов вообще.
  const счётБезПодписи = поднятьОчки(исходник, { telegram: false, отвечает: function () { return { ок: true, билет: 'x', причина: '' }; } });
  const ручкаСчётБезПодписи = счётБезПодписи.окно.ОчкиРейтинга.взятьБилетСчёта('змейка', 'classic');
  await дождаться();
  const итогСчётБезПодписи = await счётБезПодписи.окно.ОчкиРейтинга.сдатьСчёт(ручкаСчётБезПодписи, { счёт: 5 });
  проверить(счётБезПодписи.запросы.length === 0, '14: без подписи Telegram — ноль запросов на билет-счёта (получили: ' + счётБезПодписи.запросы.length + ')');
  проверить(itogСчётаОкЛожь(итогСчётБезПодписи), '14б: без подписи Telegram «сдатьСчёт» отвечает тихим отказом');

  const счётБезСети = поднятьОчки(исходник, {
    безСети: true,
    отвечает: function () { return { ок: true, билет: 'x', зерно: 1, причина: '' }; }
  });
  const ручкаСчётБезСети = счётБезСети.окно.ОчкиРейтинга.взятьБилетСчёта('змейка', 'classic');
  await дождаться();
  const итогСчётБезСети = await счётБезСети.окно.ОчкиРейтинга.сдатьСчёт(ручкаСчётБезСети, { счёт: 5 });
  проверить(счётБезСети.запросы.length === 0, '14в: без window.Сеть — ноль запросов на билет-счёта (получили: ' + счётБезСети.запросы.length + ')');
  проверить(itogСчётаОкЛожь(итогСчётБезСети), '14г: без window.Сеть «сдатьСчёт» отвечает тихим отказом (получили: ' + JSON.stringify(итогСчётБезСети) + ')');
}

/** Отказ «сдатьСчёт» — ok:false, улучшение:false, значение:null, без исключений. */
function itogСчётаОкЛожь(итог) {
  return Boolean(итог) && итог.ок === false && итог.улучшение === false && итог.значение === null;
}

/** Отказ «сдать» — ok:false и 0 очков, без исключений и без числа NaN. */
function itogОкЛожь(итог) {
  return Boolean(итог) && итог.ок === false && итог.очков === 0;
}

