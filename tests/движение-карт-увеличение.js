'use strict';
/* =====================================================================
   Движение карт в увеличенном окне.

   Оформитель увеличивает окно приложения на планшете и мониторе
   («transform: scale», 820×1180 → 1,3). Карта летит «первым-последним-
   переворотом»: первый кадр полёта обязан поставить её ровно туда, откуда
   она летит. Меряем это на пробной карте внутри игрового экрана:
     перелёт — карта была в точке А, стала в Б: первый кадр — в А;
     прилёт  — новая карта из «родины» (как из колоды): первый кадр —
               в середине родины.
   Ломающий прогон: страница получает js/движение-карт.js ДО поправки
   (слепок из коммита) — на планшете промах обязан быть больше 20 точек.

   Написал разработчик (11 сентября); тестировщик перенёс в tests/.
   У разработчика старый файл лежал рядом копией; здесь он берётся из
   git — из коммита 7b4bd01 (8 сентября), последнего, где файл менялся
   до поправки. Привязка к номеру, а не к «HEAD», нарочная: после коммита
   штаба HEAD будет уже с поправкой, и ломающий прогон тихо позеленел бы.
   В сам стол игра садится без нажатий (ИграСБотами + начатьПартию) —
   путь через лобби здесь не нужен, его проверяет tests/лобби-в1.js.

   Запуск: node tests/движение-карт-увеличение.js [порт] [коммит-до-поправки]
   ===================================================================== */
const path = require('path');
const { execFileSync } = require('child_process');
const { chromium, безTelegram, перехватить } = require(path.join(__dirname, 'браузер-робот.js'));
const { сестьБезНажатий } = require(path.join(__dirname, 'сесть-за-стол.js'));

const КОРЕНЬ = path.join(__dirname, '..');
const АДРЕС = 'http://127.0.0.1:' + (process.argv[2] || '8080') + '/';
const КОММИТ_ДО_ПОПРАВКИ = process.argv[3] || '7b4bd01';
const СТАРЫЙ_ФАЙЛ = execFileSync('git', ['show', КОММИТ_ДО_ПОПРАВКИ + ':js/движение-карт.js'],
  { cwd: КОРЕНЬ, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 });

let провалов = 0;
function надо(условие, слова) {
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}

async function замерить(браузер, ширина, высота, старыйФайл) {
  const стр = await браузер.newPage({ viewport: { width: ширина, height: высота } });
  const ошибки = [];
  стр.on('pageerror', (о) => ошибки.push(о.message));
  if (старыйФайл) {
    await перехватить(стр, /\/js\/движение-карт\.js(\?|$)/, (путь) =>
      путь.fulfill({ status: 200, contentType: 'application/javascript; charset=utf-8', body: СТАРЫЙ_ФАЙЛ }));
  } else {
    await безTelegram(стр);
  }
  стр.on('console', (з) => {
    // Скрипт Telegram стенд не пускает нарочно — его отказ не считаем.
    const откуда = (з.location && з.location().url) || '';
    if (з.type() === 'error' && откуда.indexOf('telegram-web-app.js') === -1) ошибки.push('консоль: ' + з.text());
  });
  await стр.goto(АДРЕС);
  try {
    await стр.waitForFunction(() => typeof настройкиИгрыСБотами !== 'undefined' && window.ДвижениеКарт, null, { timeout: 10000 });
  } catch (о) {
    const что = await стр.evaluate(() => ({ игра: typeof настройкиИгрыСБотами, движение: typeof window.ДвижениеКарт }));
    throw new Error('страница не поднялась: ' + JSON.stringify(что) + ' ошибки: ' + ошибки.join(' | '));
  }
  await сестьБезНажатий(стр, { игроков: 2 });
  await стр.waitForTimeout(500);
  const ответ = await стр.evaluate(() => {
    const Д = window.ДвижениеКарт;
    const экран = document.getElementById('экран-игры');
    const ц = (р) => ({ x: р.left + р.width / 2, y: р.top + р.height / 2 });
    const врозь = (а, б) => Math.round(Math.hypot(ц(а).x - ц(б).x, ц(а).y - ц(б).y));
    const поставить = (узел, x, y) => { узел.style.position = 'absolute'; узел.style.left = x + 'px'; узел.style.top = y + 'px'; };
    const первыйКадр = (узел) => { for (const а of узел.getAnimations()) { а.pause(); а.currentTime = 0; } return узел.getBoundingClientRect(); };

    // Перелёт: А (40,120) → Б (240,320).
    const карта = document.createElement('div');
    карта.className = 'карта';
    поставить(карта, 40, 120);
    Д.началоКадра();
    Д.узел('проба-перелёта', () => карта);
    экран.appendChild(карта);
    Д.конецКадра();
    const было = карта.getBoundingClientRect();
    Д.началоКадра();
    Д.узел('проба-перелёта', () => карта);
    поставить(карта, 240, 320);
    Д.конецКадра();
    const перелётМимо = врозь(первыйКадр(карта), было);
    const анимацийПерелёта = карта.getAnimations().length;

    // Прилёт: родина в (60,100), новая карта встаёт в (260,360).
    const родина = document.createElement('div');
    поставить(родина, 60, 100);
    родина.style.width = '60px';
    родина.style.height = '84px';
    экран.appendChild(родина);
    const новая = document.createElement('div');
    новая.className = 'карта';
    Д.началоКадра();
    Д.узел('проба-прилёта', () => новая, { родина: родина });
    поставить(новая, 260, 360);
    экран.appendChild(новая);
    Д.конецКадра();
    const прилётМимо = врозь(первыйКадр(новая), родина.getBoundingClientRect());
    const анимацийПрилёта = новая.getAnimations().length;

    const увеличение = экран.getBoundingClientRect().width / экран.offsetWidth;
    Д.забытьВсё();
    карта.remove(); новая.remove(); родина.remove();
    return { перелётМимо, прилётМимо, анимацийПерелёта, анимацийПрилёта,
             увеличение: Math.round(увеличение * 100) / 100 };
  });
  ответ.ошибки = ошибки;
  await стр.close();
  return ответ;
}

(async () => {
  const браузер = await chromium.launch();

  console.log('=== Телефон 390×844 ===');
  const т = await замерить(браузер, 390, 844, false);
  надо(т.увеличение === 1, 'увеличения нет: ' + т.увеличение);
  надо(т.анимацийПерелёта > 0 && т.анимацийПрилёта > 0, 'оба полёта вправду запустились');
  надо(т.перелётМимо <= 2 && т.прилётМимо <= 2, 'первый кадр на месте: перелёт мимо ' + т.перелётМимо + ', прилёт мимо ' + т.прилётМимо);

  console.log('=== Планшет 820×1180 ===');
  const п = await замерить(браузер, 820, 1180, false);
  надо(п.увеличение > 1.2, 'окно увеличено: ' + п.увеличение);
  надо(п.анимацийПерелёта > 0 && п.анимацийПрилёта > 0, 'оба полёта вправду запустились');
  надо(п.перелётМимо <= 2 && п.прилётМимо <= 2, 'первый кадр на месте: перелёт мимо ' + п.перелётМимо + ', прилёт мимо ' + п.прилётМимо);

  console.log('=== Ломающий прогон: планшет, js/движение-карт.js из ' + КОММИТ_ДО_ПОПРАВКИ + ' (до поправки) ===');
  const с = await замерить(браузер, 820, 1180, true);
  надо(с.анимацийПерелёта > 0 && с.анимацийПрилёта > 0, 'старый файл подменён и полёты запустились');
  надо(с.перелётМимо > 20 && с.прилётМимо > 20, 'без поправки промах виден: перелёт ' + с.перелётМимо + ', прилёт ' + с.прилётМимо + ' точек');

  const ошибки = [].concat(т.ошибки, п.ошибки, с.ошибки);
  надо(ошибки.length === 0, 'ошибок страницы нет' + (ошибки.length ? ': ' + ошибки.join(' | ') : ''));
  await браузер.close();
  console.log('Итог: провалов ' + провалов);
  process.exit(провалов ? 1 : 0);
})().catch((о) => { console.error('проверка упала: ' + (о && о.stack || о)); process.exit(2); });
