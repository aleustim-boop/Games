// Проверка тестировщика: дверь «завершить» на столе ШАШЕК (js/шашки-экран.js),
// прокси js/шашки-телеграм.js и перехват «‹» в js/шашки-режимы.js,
// штаб/план-выход-из-партии.md, этап Э4 + доп. поручение штаба (защита от
// двойной сдачи по сети, перехват «‹» на столе).
// Запуск:
//   node tests/выход-шашки.js                    — обычный прогон, ждём 0 провалов
//   node tests/выход-шашки.js --файл <путь>      — тот же набор проверок, но код
//     js/шашки-экран.js берётся не с диска проекта, а из файла по указанному пути
//     (для ломающего запуска: путь ведёт на испорченную КОПИЮ во временной папке,
//     файл проекта эта проверка никогда не трогает и не портит).
//   node tests/выход-шашки.js --файл-режимов <путь> — то же самое, но для
//     js/шашки-режимы.js (сценарий «‹» на столе): путь тоже ведёт на копию.
//
// Устройство. jsdom в проекте нет, а js/шашки-экран.js — 3000+ строк браузерного
// кода в замыкании: полноценный DOM ему не нужен, нужны ровно те узлы и методы,
// которыми он пользуется (тот же приём, что в tests/лист-ещё-завершить.js, только
// с более широким generic-узлом — файл трогает куда больше id и классов). Сам
// лист «⋯» (js/лист-ещё.js) здесь не грузится и не проверяется — это чужой файл,
// его дверь «завершить» уже проверена в tests/лист-ещё-завершить.js. Вместо
// настоящего листа подставлен мок, перехватывающий объект «двери» из вызова
// window.ЛистЕщё.подключить({...}) — так проверка бьёт напрямую по контракту
// двери (видна/действие/текст/пауза/продолжить), который экран обязан выдержать.
// js/шашки-правила.js — настоящий, дуальный модуль (window.ШашкиПравила и
// module.exports), грузится в ТОЙ ЖЕ песочнице vm, что и экран (не через require
// в основной realm) — иначе Set/Map партии и Set/Map экрана были бы из разных
// реалмов, и это когда-нибудь аукнется на сравнениях.
//
// js/шашки-режимы.js (кнопка «‹» на столе) грузится в СВОЕЙ отдельной лёгкой
// песочнице (собратьРежимы) — этот файл не знает о партии и правилах, ему
// нужны только кнопки и экраны выбора соперника, а window.ШашкиЭкран.
// спроситьЗавершить подменён управляемым шпионом.

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const КОРЕНЬ = path.join(__dirname, '..');
const ПУТЬ_ПРАВИЛ = path.join(КОРЕНЬ, 'js', 'шашки-правила.js');

function аргумент(имя) {
  const индекс = process.argv.indexOf(имя);
  return индекс !== -1 ? process.argv[индекс + 1] : null;
}

const путьКЭкрану = аргумент('--файл') || path.join(КОРЕНЬ, 'js', 'шашки-экран.js');
const путьКРежимам = аргумент('--файл-режимов') || path.join(КОРЕНЬ, 'js', 'шашки-режимы.js');

/* ---------- лёгкий поддельный DOM: один generic-узел на все теги ---------- */

function создатьЭлемент(тег, реестр) {
  const классы = new Set();
  const слушатели = {};
  const атрибуты = {};
  let _id = '';
  const эл = {
    tagName: тег,
    children: [],
    parentNode: null,
    textContent: '',
    innerHTML: '',
    disabled: false,
    style: {},
    classList: {
      add: function (c) { классы.add(c); },
      remove: function (c) { классы.delete(c); },
      contains: function (c) { return классы.has(c); },
      toggle: function (c, force) {
        const есть = классы.has(c);
        const нужно = force === undefined ? !есть : Boolean(force);
        if (нужно) классы.add(c); else классы.delete(c);
        return нужно;
      }
    },
    setAttribute: function (k, v) { атрибуты[k] = String(v); },
    getAttribute: function (k) { return (k in атрибуты) ? атрибуты[k] : null; },
    removeAttribute: function (k) { delete атрибуты[k]; },
    addEventListener: function (тип, fn) { (слушатели[тип] = слушатели[тип] || []).push(fn); },
    click: function () {
      const событие = { target: эл, stopPropagation: function () {} };
      (слушатели.click || []).forEach(function (fn) { fn(событие); });
    },
    appendChild: function (реб) {
      if (реб && реб._isFragment) {
        реб.children.slice().forEach(function (внук) { эл.appendChild(внук); });
        реб.children.length = 0;
        return реб;
      }
      эл.children.push(реб);
      реб.parentNode = эл;
      return реб;
    },
    remove: function () {
      if (!эл.parentNode) return;
      const у = эл.parentNode;
      const индекс = у.children.indexOf(эл);
      if (индекс !== -1) у.children.splice(индекс, 1);
      эл.parentNode = null;
    },
    querySelector: function (sel) { return найтиПоКлассу(эл, единственныйКласс(sel)); },
    querySelectorAll: function (sel) { return найтиВсеПоКлассу(эл, единственныйКласс(sel)); },
    closest: function (sel) {
      const класс = единственныйКласс(sel);
      let узел = эл;
      while (узел) {
        if (узел.classList && узел.classList.contains(класс)) return узел;
        узел = узел.parentNode;
      }
      return null;
    },
    focus: function () {}
  };
  Object.defineProperty(эл, 'id', {
    get: function () { return _id; },
    set: function (значение) { _id = значение; if (реестр) реестр.set(значение, эл); }
  });
  Object.defineProperty(эл, 'className', {
    get: function () { return Array.from(классы).join(' '); },
    set: function (значение) {
      классы.clear();
      String(значение).split(/\s+/).filter(Boolean).forEach(function (c) { классы.add(c); });
    }
  });
  Object.defineProperty(эл, 'firstChild', {
    get: function () { return эл.children.length ? эл.children[0] : null; }
  });
  return эл;
}

/** Один класс из селектора вида «.класс» (querySelector в файле всегда так и зовёт). */
function единственныйКласс(sel) {
  return String(sel).replace(/^\./, '').split(':')[0].split('.')[0];
}

function найтиПоКлассу(корень, класс) {
  for (let i = 0; i < корень.children.length; i++) {
    const реб = корень.children[i];
    if (реб.classList.contains(класс)) return реб;
    const вложенный = найтиПоКлассу(реб, класс);
    if (вложенный) return вложенный;
  }
  return null;
}

function найтиВсеПоКлассу(корень, класс) {
  const найдено = [];
  (function обойти(узел) {
    for (let i = 0; i < узел.children.length; i++) {
      const реб = узел.children[i];
      if (реб.classList.contains(класс)) найдено.push(реб);
      обойти(реб);
    }
  })(корень);
  return найдено;
}

/** Создать document с ровно тем набором id, которые js/шашки-экран.js читает
 *  через getElementById БЕЗ проверки на null (упасть на «.addEventListener»
 *  чужого отсутствующего узла — не про эту проверку, здесь смотрим на дверь). */
function создатьDocument() {
  const реестр = new Map();
  const слушателиДокумента = {};
  const body = создатьЭлемент('body', реестр);

  const document = {
    body: body,
    createElement: function (тег) { return создатьЭлемент(тег, реестр); },
    createDocumentFragment: function () {
      const фрагмент = создатьЭлемент('#fragment', null);
      фрагмент._isFragment = true;
      return фрагмент;
    },
    getElementById: function (id) { return реестр.get(id) || null; },
    querySelector: function (sel) { return найтиПоКлассу(body, единственныйКласс(sel)); },
    /** Единственный сложный паттерн в файле: «#id > .класс(.класс2)*»
     *  (видимыйОсновнойЭкран и оба MutationObserver-сторожа). Другого
     *  querySelectorAll файл не зовёт — расширять не нужно. */
    querySelectorAll: function (sel) {
      const совпадение = String(sel).match(/^#([^\s>]+)\s*>\s*((?:\.[^\s.]+)+)$/);
      if (!совпадение) return [];
      const родитель = реестр.get(совпадение[1]);
      if (!родитель) return [];
      const классы = совпадение[2].match(/\.[^.]+/g).map(function (c) { return c.slice(1); });
      return родитель.children.filter(function (реб) {
        return классы.every(function (c) { return реб.classList.contains(c); });
      });
    },
    addEventListener: function (тип, fn) { (слушателиДокумента[тип] = слушателиДокумента[тип] || []).push(fn); },
    _зарегистрировать: function (id, эл) { реестр.set(id, эл); }
  };
  document.body.appendChild = document.body.appendChild; // без изменений, для наглядности
  return document;
}

/** Построить разметку стола шашек: все id, что файл читает без null-проверки,
 *  плюс #приложение с тремя «.экран» — минимум для видимыйОсновнойЭкран(). */
