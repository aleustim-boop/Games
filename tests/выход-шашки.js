  const ОБЯЗАТЕЛЬНЫЕ_ID = [
    'доска', 'строка-хода', 'панель-сверху', 'панель-снизу', 'имя-сверху', 'имя-снизу',
    'цвет-сверху', 'цвет-снизу', 'счёт-сверху', 'счёт-снизу', 'подзаголовок-контроля',
    'часы-сверху', 'часы-снизу', 'часы-сверху-текст', 'часы-снизу-текст', 'последний-ход',
    'экран-итога', 'заголовок-итога', 'причина-итога', 'серия-шашек',
    'кнопка-с-ботом', 'кнопка-вдвоём', 'кнопка-метки', 'кнопка-ещё', 'кнопка-ещё-с-ботом',
    'кнопка-рекорды', 'кнопка-рекорды-итог', 'кнопка-другой-соперник',
    'кнопка-отменить-ход', 'кнопка-ничьей', 'кнопка-сдаться',
    'уровень-лёгкий', 'уровень-обычный', 'уровень-сложный',
    'время-нет', 'время-пять', 'время-блиц', 'время-рапид',
    'экран-ленты-шашек', 'лента-шашек', 'кнопка-лента-шашки-назад',
    'кнопка-правила-назад', 'кнопка-рекорды-назад'
  ];
  ОБЯЗАТЕЛЬНЫЕ_ID.forEach(function (id) {
    const узел = document.createElement('div');
    узел.id = id;
    document.body.appendChild(узел);
  });

  // «Доска» — узел с известным родителем (рамкой) НЕ даём нарочно: файл
  // достаёт узелРамки как parentElement доски и, если он есть, лезет
  // в querySelectorAll('.метка-буква, .метка-цифра') — селектор с запятой,
  // который эта проверка не обязана понимать (в реальном html он есть,
