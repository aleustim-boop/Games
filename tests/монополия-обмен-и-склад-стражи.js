/* =======================================================================
   ЧАСТЬ Б. СКЛАД СНОВА ПОЛОН — АУКЦИОН ЗА ЗДАНИЕ СНИМАЕТСЯ С ОЧЕРЕДИ.
   ======================================================================= */

const ТЕКСТ_СКЛАДА = 'Зданий в банке снова хватает — стройте обычным путём';

const own = (g, p, ids, level = 0) =>
  ids.forEach((id) => Object.assign(g.properties[id], { owner: p, level }));

function найтиСобытие(g, kind, доп = {}) {
  return g.events.find(
    (e) => e.kind === kind && Object.keys(доп).every((ключ) => e[ключ] === доп[ключ]),
  );
}

function проверитьAssert(g, название) {
  try {
    P.assert(g);
    отметить(true, название + ': итоговое состояние партии не нарушает внутренних правил (assert)');
  } catch (e) {
    отметить(false, название + ': assert упал: ' + e.message);
  }
}

/* Доигрывает ЧУЖИЕ (не строительные) аукционы, которые оставляет за
   собой сдавшийся: у него есть свой отдельный квартал (группа 6:
   31,32,34) — bankrupt() честно выставляет эти улицы на обычный,
   не building, аукцион. Нас интересует не он, а что происходит с
   ОСНОВНЫМ аукционом за здание — поэтому пасуем за всех, пока не
   вернёмся либо к нему, либо партия вообще покинула этап "auction"
   (пример и приём — tests/монополия-сдача-в-аукционе-за-здание.js). */
function пропуститьЧужиеАукционы(g) {
  let шагов = 0;
  while (g.phase === 'auction' && !g.auction.building && шагов++ < 40) {
    const актёр = P.who(g);
    P.action(g, актёр, { type: 'pass' });
  }
}
function сдаться(g, p) {
  P.action(g, p, { type: 'surrender' });
  пропуститьЧужиеАукционы(g);
}

/* Стол для сценария Б: у А(0), Б(1), В(2) — по своему целому кварталу
   на уровне 0 (все трое могут построить следующий, ПОСЛЕДНИЙ в банке,
   дом). У Г(3) — ОТДЕЛЬНЫЙ квартал (группа 6: 31,32,34), никак не
   связанный с этим аукционом, целиком застроенный до уровня 4 (у него
   есть монополия, застройка ровная — level>0, следующая ступень была
   бы отелем, поэтому Г и не попадает в "eligible" аукциона за ДОМ).
   Остальные клетки — заполнители банка (владелец не важен, stock()
   считает по всем клеткам подряд), подобраны так, чтобы в банке
   остался РОВНО 1 дом:
     группа 3 (А, 16/18/19) уровень 0      =  0
     группа 1 (Б, 6/8/9)   уровень 0       =  0
     группа 2 (В, 11/13/14) уровень 0      =  0
     группа 6 (Г, 31/32/34) уровень 4      = 12
     группа 4 (21/23/24) заполнитель ур.1  =  3
     группа 5 (26/27/29) заполнитель ур.4  = 12
     группа 7 (37/39)   заполнитель ур.2   =  4
                                    итого  = 31  →  32-31 = 1 дом в банке
   Когда Г сдаётся, его 12 домов возвращаются в банк — 31-12=19, в
   банке становится 32-19=13 домов (больше 1). */
function столСклад(seed) {
  const g = P.create(4, seed);
  g.turn = 0;
  g.phase = 'manage';
  g.queue = [];
  own(g, 0, [16, 18, 19], 0); // А
  own(g, 1, [6, 8, 9], 0); // Б
  own(g, 2, [11, 13, 14], 0); // В
  own(g, 3, [31, 32, 34], 4); // Г — отдельный, не связанный с аукционом квартал
  g.properties[21].level = 1;
  g.properties[23].level = 1;
  g.properties[24].level = 1;
  g.properties[26].level = 4;
  g.properties[27].level = 4;
  g.properties[29].level = 4;
  g.properties[37].level = 2;
  g.properties[39].level = 2;
  return g;
}

console.log('\n--- Б: у сдающегося есть ДРУГОЙ квартал с домами — при его сдаче склад снова полон ---');
try {
  const g = столСклад(401);

  отметить(P.stock(g).houses === 1, 'Б: раскладка верна — в банке ровно 1 дом до всего');
  отметить(P.buildable(g, 0, 16) && P.buildable(g, 1, 6) && P.buildable(g, 2, 11), 'Б: А, Б и В могут построить свой следующий (последний) дом');
  отметить(!P.buildable(g, 3, 31) || g.properties[31].level === 4, 'Б: у квартала Г (31/32/34) уже уровень 4 — раскладка верна');

  P.action(g, 0, { type: 'build', id: 16 }); // А запускает аукцион за последний дом
  отметить(g.phase === 'auction' && g.auction.building, 'Б: аукцион за здание начался');
  отметить(g.auction.kind === 'house', 'Б: вид аукциона — «house» (не отель)');
  отметить(
    g.auction.eligible.slice().sort((x, y) => x - y).join(',') === '0,1,2',
    'Б: претендентов трое — А, Б, В (игрок Г в претенденты не попал, его группа уже на уровне 4 — следующая ступень была бы отелем)',
  );

  сдаться(g, 3); // сдаётся Г — у него ЕСТЬ дома, но в ДРУГОМ, не связанном с аукционом квартале

  отметить(g.players[3].out === true, 'Б: сдавшийся Г действительно выбыл (out)');
  отметить(g.phase === 'manage', 'Б: партия вернулась в живой этап «manage» (сейчас: «' + g.phase + '»)');
  отметить(g.auction === null, 'Б: g.auction пуст — аукцион за здание больше не идёт');
  отметить(P.stock(g).houses > 1, 'Б: склад снова полон, домов больше одного (сейчас: ' + P.stock(g).houses + ')');
  отметить(
    Boolean(найтиСобытие(g, 'auctionEmpty', { text: ТЕКСТ_СКЛАДА })),
    'Б: в журнале есть «склад снова полон» дословно (auctionEmpty, текст «' + ТЕКСТ_СКЛАДА + '»)',
  );
  отметить(!найтиСобытие(g, 'auctionWin'), 'Б: победителя аукциона за здание нет — никто из А/Б/В его не выиграл');

  проверитьAssert(g, 'Б');

  // buildable снова возможен у того, кто может строить — проверяем и
  // флагом, и настоящим действием (последний дом банка больше не
  // «последний», обычная постройка не должна снова запускать аукцион).
  отметить(P.buildable(g, 0, 16), 'Б: P.buildable(g,0,16) снова true после снятия аукциона');
  const уровеньДо = g.properties[16].level,
    деньгиДо = g.players[0].money;
  let упалоНаПостройке = null;
  try {
    P.action(g, 0, { type: 'build', id: 16 }); // обычная постройка, без аукциона
  } catch (e) {
    упалоНаПостройке = e;
  }
  отметить(!упалоНаПостройке, 'Б: обычная постройка последнего (по факту — уже не последнего) дома прошла без ошибок' + (упалоНаПостройке ? ' (упало: ' + упалоНаПостройке.message + ')' : ''));
  отметить(g.properties[16].level === уровеньДо + 1, 'Б: дом действительно построен (уровень вырос: ' + уровеньДо + ' → ' + g.properties[16].level + ')');
  отметить(g.players[0].money === деньгиДо - 100, 'Б: деньги списаны как за обычную постройку, без аукциона (было ' + деньгиДо + ', стало ' + g.players[0].money + ')');
  отметить(g.phase === 'manage', 'Б: после обычной постройки партия по-прежнему в «manage» (не auction)');

  проверитьAssert(g, 'Б (после постройки)');
} catch (e) {
  отметить(false, 'Б: сценарий упал целиком, дальше не выполнился (' + e.message + ')');
}

