  отметить(!ошибка, 'А2: новый offer после reject прошёл без ошибок' + (ошибка ? ' (упало: ' + ошибка.message + ')' : ''));
  отметить(g.phase === 'trade' && g.trade && g.trade.from === 1, 'А2: новое предложение действительно создано');
