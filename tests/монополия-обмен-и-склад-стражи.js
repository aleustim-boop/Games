/* =====================================================================
   ДВЕ НЕЗАВИСИМЫЕ ПРАВКИ В js/монополия-правила.js: «ОДНО ПРЕДЛОЖЕНИЕ
   ОБМЕНА РАЗОМ» И «СКЛАД СНОВА ПОЛОН — АУКЦИОН ЗА ЗДАНИЕ СНИМАЕТСЯ».

   А) apply(), ветка type === "offer" (~строка 683). Если отправитель p
   НЕ на общем ходу (p !== g.turn) и у него уже висит СВОЁ неотвеченное
   предложение (g.phase === "trade" && g.trade.from === p) — второй
   offer отклоняется словами «У вас уже есть предложение — дождитесь
   ответа или отзовите его». cancel (отзыв своего предложения) или
   accept/reject соперника обнуляют g.trade и возвращают g.phase из
   g.resume — после этого новый offer снова проходит.

   Б) auction(g, task) (~строки 186–223). После проверки «все
   претенденты выбыли» — вторая проверка склада: если для вида
   задания (house/hotel по buildingKind) в банке СНОВА больше 1
   штуки — задание аукциона снимается с очереди (событие "auctionEmpty",
   текст «Зданий в банке снова хватает — стройте обычным путём»), без
   создания g.auction и без списания чьих-либо ставок. Склад может
   пополниться, пока аукцион ждал в очереди или уже шёл: кто-то
   сдался, и его ДРУГОЙ, не связанный с этим аукционом квартал с
   домами вернулся в банк.

   Проверяем здесь (только node, чистые правила, без браузера и
   сервера):
     А1) offer → второй offer того же неответившего отправителя падает
         ровно с нужным текстом → cancel → offer снова проходит
     А2) offer → reject соперника → новый offer снова проходит
     А3) чужое предложение висит, ходящий по общему ходу игрок (p ===
         g.turn) шлёт offer — какой отказ даёт игра в этом случае,
         фиксируем КАК ЕСТЬ (не придумываем ожидание, только проверяем,
         что отказ не пустой)
     Б)  стол, где у сдающегося (Г) есть ОТДЕЛЬНЫЙ, не связанный с
         начатым аукционом квартал с домами (level=4 > 0); в банке
         остаётся ровно 1 дом, аукцион за последний дом идёт с тремя
         претендентами (А, Б, В); Г сдаётся. Побочные (не строительные)
         аукционы за его обычную собственность доигрываются пасами,
         затем аукцион за здание сам перезапускается — склад снова
         полон (12 домов вернулись), он снимается событием
         "auctionEmpty", партия возвращается в живой этап "manage", и
         после этого построить последний дом обычным путём снова можно.

   Запуск:
       node tests/монополия-обмен-и-склад-стражи.js

   Ломающие запуски (оба обязаны покраснеть; настоящий файл проекта не
   трогаем — работаем с копиями во временной папке):
       node tests/монополия-обмен-и-склад-стражи.js <путь-к-копии-правил>

   Копия №1 (валит сценарии А1—А3): скопировать js/монополия-правила.js
   и js/монополия-данные.js рядом друг с другом во временную папку, в
   копии правил вырезать из ветки type === "offer" ровно этот кусок
   (саму новую проверку «уже есть предложение»):
     need(
       !(p !== g.turn && g.phase === "trade" && g.trade.from === p),
       "У вас уже есть предложение — дождитесь ответа или отзовите его",
     );
   — тогда игрок сможет заново и заново слать offer поверх своего же
   неотвеченного предложения, и сценарий А1 не увидит ожидаемого отказа.

   Копия №2 (валит сценарий Б): в той же копии правил (или в отдельной)
   из функции auction() вырезать вторую проверку склада — весь блок
     if (
       task.building &&
       stock(g)[buildingKind === "hotel" ? "hotels" : "houses"] > 1
     ) {
       g.queue.shift();
       event(g, "Зданий в банке снова хватает — стройте обычным путём", {
         kind: "auctionEmpty",
       });
       pump(g);
       return;
     }
   — тогда аукцион за последний дом перезапустится как обычно даже
   когда склад banка снова полон, событие "auctionEmpty" (по этой
   причине) не появится, и сценарий Б покраснеет.
   ===================================================================== */

