/* ---- HTTP и подпись Telegram ---- */
function запрос(путь, тело) {
  return new Promise(function (готово) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const req = http.request({
      host: '127.0.0.1', port: ПОРТ, method: 'POST', path: encodeURI(путь),
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let куски = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (к) { куски += к; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(куски); } catch (е) { разобрано = { сырое: куски }; }
        готово({ номер: ответ.statusCode, данные: разобрано || {}, текст: куски });
      });
    });
    req.on('error', function (е) { готово({ номер: 0, данные: { ошибка: String(е.message) }, текст: '' }); });
    req.write(данные);
    req.end();
  });
}

function подписать(поля) {
  const строки = Object.keys(поля).map(function (к) { return к + '=' + поля[к]; }).sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(ТОКЕН).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}
function initDataДля(номер) {
  const поля = {
    query_id: 'AAРевью' + номер,
    user: JSON.stringify({ id: номер, first_name: 'Игрок' + номер }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  поля.hash = подписать(поля);
  return Object.keys(поля).map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(поля[к]); }).join('&');
}

function создать(номер, игра, доп) {
  return запрос('/создать', Object.assign(
    { имя: 'Хозяин' + номер, метка: 'metka-hoz-' + номер, initData: initDataДля(номер), игра: игра }, доп));
}
/** Вход по коду. номер = null — гость без подписи Telegram. */
function войти(код, номер, доп) {
  const тело = { код: код, имя: 'Гость', метка: 'metka-gost-' + (номер || 'bez-podpisi') };
  if (номер) тело.initData = initDataДля(номер);
  return запрос('/войти', Object.assign(тело, доп));
}
function выйти(код, пропуск) {
  return запрос('/выйти', { код: код, пропуск: пропуск });
}
function состояние(код, пропуск) {
  return запрос('/состояние', { код: код, пропуск: пропуск });
}
function отметить(номер, id, что) {
  return запрос('/приглашение-событие', { initData: initDataДля(номер), id: id, что: что });
}

const АДРЕС_БУКВАМИ = Buffer.from('http://127.0.0.1:' + ПОРТ, 'utf8').toString('base64')
  .replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
function ссылкаЗаСтол(игра, код) {
  const строка = названия.ИГРЫ.find(function (с) { return с.игра === игра; }) || {};
  const метка = строка.метка || '';
  return 'https://t.me/' + ИМЯ_БОТА + '/BoardGames?startapp=' + (метка ? метка + '_' : '') + код + '-' + АДРЕС_БУКВАМИ;
}
/** Позвать за стол — номер приглашения или ''. */
async function позвать(номер, игра, код) {
  const ответ = await запрос('/приглашение', { initData: initDataДля(номер), ссылка: ссылкаЗаСтол(игра, код) });
  return (ответ.данные && ответ.данные.приглашение) || '';
}
/** События записи учёта: [{ что, кто }]. */
function события(id) {
  const з = приглашения.запись(id);
  return з ? з.события : [];
}
function входов(id, кто) {
  return события(id).filter(function (с) {
    return с.что === 'вход' && (кто === undefined || (с.кто || null) === кто);
  }).length;
}

/* ---- (а) гость без подписи ---- */
async function случайБезПодписи() {
  console.log('\n(а) Гость без подписи по номеру приглашения');
  const хоз = 700001;
  const стол = await создать(хоз, 'нарды');
  проверить('(а) стол создан', стол.номер === 200 && Boolean(стол.данные.код), стол.текст);
  const код = стол.данные.код;
  const id = await позвать(хоз, 'нарды', код);
  проверить('(а) номер приглашения выдан', /^[a-z0-9]{4,16}$/.test(id), '«' + id + '»');
  const гость = await войти(код, null, { приглашение: id });
  проверить('(а) гость без подписи за стол сел', гость.номер === 200 && Boolean(гость.данные.пропуск), гость.текст);
  проверить('(а) вход без подписи не дал «вход» в учёт', входов(id) === 0,
    JSON.stringify(события(id)));
  проверить('(а) и «старт» тоже не дал', !события(id).some(function (с) { return с.что === 'старт'; }),
    JSON.stringify(события(id)));

  // Сверка: подписанный друг по той же схеме «вход» даёт.
  const хоз2 = 700002;
  const стол2 = await создать(хоз2, 'нарды');
  const id2 = await позвать(хоз2, 'нарды', стол2.данные.код);
  const друг = await войти(стол2.данные.код, 700003, { приглашение: id2 });
  проверить('(а) сверка: подписанный друг сел', друг.номер === 200, друг.текст);
  проверить('(а) сверка: подписанный друг дал «вход»', входов(id2, 700003) === 1, JSON.stringify(события(id2)));
}

