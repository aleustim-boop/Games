function ломать() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'сыграть-с-другом-ревью-поломки-'));
  let бед = 0;
  ПОЛОМКИ.forEach(function (поломка, номер) {
    const исходник = fs.readFileSync(path.join(КОРЕНЬ, 'server', поломка.файл), 'utf8');
    const сколько = исходник.split(поломка.было).length - 1;
    if (сколько !== 1) {
      бед++;
      console.log('  ПРОВАЛ ' + поломка.имя + ': откатываемый кусок найден ' + сколько + ' раз (нужно ровно 1)');
      return;
    }
    const копия = path.join(папка, номер + '-' + поломка.файл);
    fs.writeFileSync(копия, исходник.replace(поломка.было, поломка.стало), 'utf8');
    const довод = '--' + поломка.файл.replace('.js', '') + '=' + копия;
    const прогон = spawnSync(process.execPath, [__filename, довод], { encoding: 'utf8', timeout: 180000 });
    const вывод = (прогон.stdout || '') + (прогон.stderr || '');
    const краснеетНужное = вывод.split('\n').some(function (строка) {
      return строка.indexOf('ПРОВАЛ') !== -1 && строка.indexOf(поломка.ждём) !== -1;
    });
    const ок = прогон.status === 1 && краснеетНужное;
    if (!ок) бед++;
    console.log((ок ? '  ок     ' : '  ПРОВАЛ ') + поломка.имя + ' → код выхода ' + прогон.status +
      ', покраснел пункт ' + поломка.ждём + ': ' + (краснеетНужное ? 'да' : 'НЕТ') + '  [копия: ' + копия + ']');
    if (!ок) console.log(вывод.split('\n').filter(function (с) { return /ПРОВАЛ|Итого/.test(с); }).join('\n'));
  });
  console.log('\nЛомающих запусков: ' + ПОЛОМКИ.length + ', не покраснело как надо: ' + бед);
  try { fs.rmSync(папка, { recursive: true, force: true }); } catch (е) { /* не страшно */ }
  process.exit(бед > 0 ? 1 : 0);
}

if (process.argv.indexOf('--ломать') !== -1) {
  ломать();
  return;
}

