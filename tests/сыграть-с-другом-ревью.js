  /* У создателя стола метки нет вовсе (сервер сажает его без неё), поэтому
     «чужое место с меткой» — место друга: он сел по коду со своей вкладки. */
  const хоз = 730001;
  const друг = 730002;
  const меткаДруга = 'metka-gost-' + друг;
