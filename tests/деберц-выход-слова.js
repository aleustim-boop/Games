'use strict';
/* Деберц: слова выхода и подсветка «Вы» на итоге по согласию. Чистый node, браузера нет.

   Запуск:  node tests/деберц-выход-слова.js
   Что делает:
     1) чистые решения из настоящего js/деберц-экран.js (ДеберцВыход): режим выхода
        (сеть от трёх мест и партия идёт / вдвоём / партия кончилась / без сети / вид
        стола ещё не пришёл), слова листа «⋯» и окна, отметка «Вы» при конце по согласию;
     2) проводка в тексте экрана: дверь «завершить» листа спрашивает режим, окно
        и итог берут слова и отметку из тех же решений. Не нашли строку — провал;
     3) ломающие запуски на КОПИЯХ экрана во временной папке системы: копия портится
        одной заменой и эта же проверка (с --экран <копия>) обязана покраснеть.
   Код выхода: 0 — зелено; 1 — провал; 2 — строка для порчи не нашлась (провал тоже). */
const assert = require('node:assert/strict');
const path = require('node:path');
const os = require('node:os');
const fs = require('node:fs');
const { spawnSync } = require('node:child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const ЭКРАН = path.join(КОРЕНЬ, 'js', 'деберц-экран.js');
const МИНИМУМ_ПРОВЕРОК = 20;   // меньше — значит, часть проверок молча выпала

function довод(имя) {
  const n = process.argv.indexOf(имя);
  return n > 0 ? path.resolve(process.argv[n + 1]) : null;
}
const ФАЙЛ_ЭКРАНА = довод('--экран') || ЭКРАН;
const СТРАНИЦА = path.join(КОРЕНЬ, 'деберц.html');
const ЛИСТ = path.join(КОРЕНЬ, 'js', 'лист-ещё.js');
const ФАЙЛ_СТРАНИЦЫ = довод('--страница') || СТРАНИЦА;
const ЗАПУСК_НА_КОПИИ = Boolean(довод('--экран') || довод('--страница'));

// Слова — те, что задал штаб; проверка сверяет экран с ними, а не с собой.
const СЛОВА_БОТ = { строка: 'Выйти из партии', заголовок: 'Выйти из партии?', да: 'Выйти', нет: 'Остаться' };
const ОКНО_БОТ = { заголовок: 'Выйти из партии?', да: 'Выйти' };
const ОКНО_ПРЕЖНЕЕ = { заголовок: 'Выйти из комнаты?', да: 'Выйти из комнаты' };

const исходник = fs.readFileSync(ФАЙЛ_ЭКРАНА, 'utf8');
const В = require(ФАЙЛ_ЭКРАНА).ДеберцВыход;

let проверок = 0;
let провалов = 0;
function проверка(имя, дело) {
  проверок++;
  try { дело(); console.log('  ок      ' + имя); }
  catch (e) { провалов++; console.log('  ПРОВАЛ  ' + имя + ' — ' + (e && e.message)); }
}

/* Проверки, читающие текст экрана: ноль найденного — провал, а не пропуск. */
function найти(шаблон, чем) {
  const найдено = исходник.match(шаблон);
  assert.ok(найдено, 'в экране не нашлось: ' + чем);
  return найдено;
}

console.log('Чистые решения выхода');
проверка('экран отдаёт ДеберцВыход наружу', () => {
  assert.ok(В && typeof В.режимВыхода === 'function' && typeof В.словаЛиста === 'function'
    && typeof В.словаОкна === 'function' && typeof В.отметкаСебя === 'function');
});
const стол = (мест, фаза) => ({ поСети: true, деберц: true, мест, фаза: фаза || 'игра' });
[3, 4].forEach(мест => проверка('сеть, ' + мест + ' места, партия идёт — «бот»', () => {
  assert.equal(В.режимВыхода(стол(мест)), 'бот');
}));
['торговля', 'взятка', 'итог'].forEach(фаза => проверка('сеть, три места, фаза «' + фаза + '» — «бот»', () => {
  assert.equal(В.режимВыхода(стол(3, фаза)), 'бот');
}));
проверка('вдвоём — прежний', () => { assert.equal(В.режимВыхода(стол(2)), 'прежний'); });
проверка('партия кончилась (три места) — прежний', () => { assert.equal(В.режимВыхода(стол(3, 'конец')), 'прежний'); });
проверка('без сети (партия с ботами) — прежний', () => {
  assert.equal(В.режимВыхода({ поСети: false, деберц: true, мест: 3, фаза: 'игра' }), 'прежний');
});
проверка('вид сетевого стола ещё не пришёл — прежний', () => {
  assert.equal(В.режимВыхода({ поСети: true, деберц: false, мест: 3, фаза: 'игра' }), 'прежний');
});
проверка('пустой вход — прежний, без падения', () => {
  assert.equal(В.режимВыхода(null), 'прежний');
  assert.equal(В.режимВыхода({}), 'прежний');
});

console.log('Слова листа «⋯» и окна');
проверка('лист, режим «бот»: все четыре слова', () => { assert.deepEqual({ ...В.словаЛиста('бот') }, СЛОВА_БОТ); });
проверка('лист, режим «прежний»: слов нет — строка «В меню» на месте', () => { assert.equal(В.словаЛиста('прежний'), null); });
проверка('окно, режим «бот»: «Выйти из партии?» и «Выйти»', () => { assert.deepEqual(В.словаОкна('бот'), ОКНО_БОТ); });
проверка('окно, режим «прежний»: слова прежние', () => { assert.deepEqual(В.словаОкна('прежний'), ОКНО_ПРЕЖНЕЕ); });
проверка('три положения дают три разных ответа сразу по входу', () => {
  const вТрёх = В.режимВыхода(стол(3)), вДвоём = В.режимВыхода(стол(2)), кончилась = В.режимВыхода(стол(3, 'конец'));
  assert.equal(В.словаЛиста(вТрёх).строка, 'Выйти из партии');
  assert.equal(В.словаЛиста(вДвоём), null);
  assert.equal(В.словаЛиста(кончилась), null);
  assert.equal(В.словаОкна(вДвоём).заголовок, 'Выйти из комнаты?');
  assert.equal(В.словаОкна(кончилась).да, 'Выйти из комнаты');
});

console.log('Отметка «Вы» на итоге');
проверка('согласие: отметки нет ни у кого', () => {
  [0, 1, 2, 3].forEach(место => assert.equal(В.отметкаСебя('согласие', место), false, 'место ' + место));
});
['победа', 'поражение', 'ничья', null].forEach(исход => проверка('исход «' + исход + '»: «Вы» отмечена, чужие нет', () => {
  assert.equal(В.отметкаСебя(исход, 0), true);
  assert.equal(В.отметкаСебя(исход, 1), false);
}));

console.log('Проводка в тексте экрана');
проверка('дверь «завершить» видна только в режиме «бот» на экране игры', () => {
  найти(/завершить:\s*\{\s*видна:[^\n]*экран--виден[^\n]*режимВыхода\(\)\s*===\s*'бот'/, 'видна() двери «завершить»');
});
проверка('дверь «завершить» отдаёт слова листа по режиму и выходит через «покинуть»', () => {
  найти(/слова:\s*\(\)\s*=>\s*window\.ДеберцВыход\.словаЛиста\(режимВыхода\(\)\)/, 'слова двери');
  найти(/действие:\s*покинуть\s*\}/, 'действие двери');
});
проверка('окно выхода берёт заголовок и «да» из словаОкна', () => {
  найти(/словаОкна\(режимВыхода\(\)\)/, 'слова окна по режиму');
  найти(/эл\('деберц-выход-заголовок'\)\.textContent\s*=\s*слова\.заголовок/, 'заголовок окна');
  найти(/эл\('деберц-выход-да'\)\.textContent\s*=\s*слова\.да/, 'кнопка «да» окна');
});
проверка('карточка итога и строка таблицы берут отметку из отметкаСебя', () => {
  найти(/toggle\('деберц-результат-команды--вы',\s*window\.ДеберцВыход\.отметкаСебя\(исход,\s*i\)\)/, 'класс карточки «Вы»');
  найти(/className\s*=\s*window\.ДеберцВыход\.отметкаСебя\(исход,\s*i\)\s*\?\s*'деберц-итог-вы'/, 'класс строки «Вы»');
});
проверка('класс «Вы» не ставится в обход отметкаСебя', () => {
  assert.ok(!/результат-команды--вы',\s*i === 0/.test(исходник), 'класс карточки снова ставится по i === 0');
  assert.ok(!/className\s*=\s*i === 0\s*\?\s*'деберц-итог-вы'/.test(исходник), 'класс строки снова ставится по i === 0');
});

console.log('Подпись строки «В меню» в разметке');
проверка('кнопка листа держит узел подписи, в который лист-ещё.js пишет слова', () => {
  // Имя класса берём из самого листа: он пишет подпись в querySelector('.<класс>') внутри строки «вМеню».
  const текстЛиста = fs.readFileSync(ЛИСТ, 'utf8');
  const блок = текстЛиста.match(/ключ === 'вМеню'[\s\S]*?querySelector\('\.([^']+)'\)[\s\S]*?подпись\.textContent\s*=/);
  assert.ok(блок, 'в js/лист-ещё.js не нашлось записи подписи в узел внутри строки «вМеню»');
  const класс = блок[1];
  const страница = fs.readFileSync(ФАЙЛ_СТРАНИЦЫ, 'utf8');
  const кнопка = страница.match(/<button[^>]*id="кнопка-лист-игры-меню"[^>]*>([\s\S]*?)<\/button>/);
  assert.ok(кнопка, 'в деберц.html не нашлась кнопка «кнопка-лист-игры-меню»');
  const узел = new RegExp('class="([^"]*\\s)?' + класс.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '(\\s[^"]*)?"');
  assert.ok(узел.test(кнопка[1]), 'внутри кнопки нет узла с классом «' + класс + '» — подпись листа молча не сменится');
});

console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);
if (проверок < МИНИМУМ_ПРОВЕРОК) { console.log('Проверок меньше ' + МИНИМУМ_ПРОВЕРОК + ' — часть выпала, это провал.'); process.exit(1); }
if (провалов > 0) process.exit(1);

/* ---------- Ломающие запуски (только в основном запуске, не в запуске на копии) ---------- */
if (!ЗАПУСК_НА_КОПИИ) {
  const ПОРЧИ = [
    ['слова листа пропали (режим «бот» без слов)', "режим === 'бот' ? СЛОВА_ЛИСТА_БОТ : null", 'null'],
    ['строка листа снова «В меню»', "строка: 'Выйти из партии'", "строка: 'В меню'"],
    ['заголовок окна снова «Выйти из комнаты?» в режиме «бот»', "{ заголовок: 'Выйти из партии?', да: 'Выйти' }", "{ заголовок: 'Выйти из комнаты?', да: 'Выйти из комнаты' }"],
    ['стол на двоих тоже с ботом', 'вход.мест > 2', 'вход.мест > 1'],
    ['после конца партии всё ещё «бот»', "&& вход.фаза !== 'конец'", ''],
    ['без сети тоже «бот»', 'вход.поСети === true && ', ''],
    ['отметка «Вы» при согласии вернулась', "место === 0 && исход !== 'согласие'", 'место === 0'],
    ['карточка «Вы» ставится по i === 0', "toggle('деберц-результат-команды--вы', window.ДеберцВыход.отметкаСебя(исход, i))", "toggle('деберц-результат-команды--вы', i === 0)"],
    ['строка таблицы «Вы» ставится по i === 0', "window.ДеберцВыход.отметкаСебя(исход, i) ? 'деберц-итог-вы'", "i === 0 ? 'деберц-итог-вы'"],
    ['дверь «завершить» видна всегда', "экран--виден') && режимВыхода() === 'бот'", "экран--виден') && true"],
    ['окно не берёт слова из словаОкна', "эл('деберц-выход-заголовок').textContent = слова.заголовок;", ''],
    // Четвёртое поле «страница»: порча идёт в копии деберц.html, а не экрана.
    ['в кнопке листа нет узла подписи (span убран)', '<span class="лист-ещё__подпись">В меню</span></button>', 'В меню</button>', 'страница'],
  ];
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'деберц-выход-слова-'));
  console.log('\nЛомающие запуски на копиях в ' + папка);
  let покраснело = 0;
  const текстСтраницы = fs.readFileSync(СТРАНИЦА, 'utf8');
  ПОРЧИ.forEach(([что, было, стало, чтоПортим], n) => {
    const наСтранице = чтоПортим === 'страница';
    const части = (наСтранице ? текстСтраницы : исходник).split(было);
    if (части.length !== 2) { console.log('  НЕТ СТРОКИ ДЛЯ ПОРЧИ (' + (части.length - 1) + ' раз): ' + что); process.exit(2); }
    const копия = path.join(папка, наСтранице ? 'деберц-страница-' + (n + 1) + '.html' : 'деберц-экран-' + (n + 1) + '.js');
    fs.writeFileSync(копия, части.join(стало));
    const запуск = spawnSync(process.execPath, [__filename, наСтранице ? '--страница' : '--экран', копия], { encoding: 'utf8' });
    const красная = запуск.status === 1;
    if (красная) покраснело++;
    console.log('  ' + (красная ? 'покраснела' : 'НЕ ПОКРАСНЕЛА (код ' + запуск.status + ')') + ' — ' + что + '  [' + копия + ']');
  });
  console.log('Поломок ' + ПОРЧИ.length + ', покраснело ' + покраснело);
  if (покраснело !== ПОРЧИ.length) process.exit(1);
}
