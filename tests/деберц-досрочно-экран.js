/**
 * Запустить настоящий экран. сеть — добавки к поддельной window.Сеть
 * (например, без текстыДосрочно — «старая сеть.js из кэша»).
 * настройки.узлы — узлы другой разметки (старая страница из кэша);
 * настройки.подготовить(память) — что лежит в памяти до запуска экрана.
 */
function запуститьЭкран(сеть = {}, настройки = {}) {
  const документ = сделатьДокумент();
  const уже = new Set();
  for (const у of настройки.узлы || узлыРазметки) {
    if (уже.has(у.id)) continue;
    уже.add(у.id);
    const узел = документ.createElement(у.тег);
    узел.id = у.id; узел.className = у.класс;
    if (у.тег === 'dialog') {
      узел.open = false;
      узел.showModal = () => { узел.open = true; };
      узел.close = () => { узел.open = false; };
    }
    документ.body.appendChild(узел);
  }
  for (const id of ЧУЖИЕ_УЗЛЫ) if (!документ.getElementById(id)) { const у = документ.createElement('button'); у.id = id; документ.body.appendChild(у); }
  /* Два узла без id, которые экран ищет по классу внутри узлов с id. */
  документ.getElementById('деберц-сведения').appendChild(документ.узел('table', { класс: 'деберц-сводка' }));
  документ.getElementById('строка-меня').appendChild(документ.узел('span', { класс: 'строка-игрока__имя' }));

  const вызовы = { предложить: 0, покинуть: 0 };
  let двериЛиста = null;
  const поддельнаяСеть = {
    текстыДосрочно,
    отправитьХод: async () => ({ принято: true }),
    предложитьЗакончить: async () => { вызовы.предложить++; return поддельнаяСеть.ответПредложения; },
    ответПредложения: { принято: true, причина: '' },
    покинутьПартию() { вызовы.покинуть++; },
    кнопкаВДрузья() {},
    ...сеть
  };
  for (const [ключ, значение] of Object.entries(сеть)) if (значение === undefined) delete поддельнаяСеть[ключ];
  const память = сделатьПамять(false);
  if (настройки.подготовить) настройки.подготовить(память);
  const окно = {
    document: документ, localStorage: память, addEventListener() {}, matchMedia: () => ({ matches: false }),
    ДеберцПравила: require('../js/деберц-правила'), ДеберцБот: require('../js/деберц-бот'),
    ДеберцПамять: require('../js/деберц-память'),
    ДеберцЗвук: { сыграть() {} },
    ДвижениеКарт: { настроить() {}, забытьВсё() {}, началоКадра() {}, конецКадра() {}, куда() {}, узел: (id, сделать) => сделать() },
    КолодаРисунок: { нарисовать: () => документ.createElement('span'), рубашка: () => документ.createElement('span') },
    ДеберцСказать: () => ({ открыть() {}, принять() {} }),
    ЛистЕщё: { подключить: н => { двериЛиста = н.двери; return { открыт: () => false, закрыть() {}, открыть() {} }; } },
    ЭкранРейтинга: { открыть() {}, открытьСчёт() {} },
    ЭкранПрофиля: { открыть() {} },
    Сеть: поддельнаяСеть
  };
  const песочница = {
    window: окно, document: документ, localStorage: память, location: { href: '' }, console,
    setTimeout, clearTimeout, requestAnimationFrame: () => 0, matchMedia: окно.matchMedia,
    ResizeObserver: class { observe() {} }
  };
  vm.createContext(песочница);
  vm.runInContext(fs.readFileSync(довод('--экран') || ЭКРАН, 'utf8'), песочница, { filename: 'деберц-экран.js' });
  const узел = id => документ.getElementById(id);
  return {
    окно, узел, вызовы, сеть: поддельнаяСеть,
    показать: вид => окно.ИграПоСети.показатьВид(вид),
    вМеню: () => двериЛиста.вМеню.действие()
  };
}

