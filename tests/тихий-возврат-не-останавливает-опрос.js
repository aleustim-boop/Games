'use strict';
// Проверка: тихий возврат (плашка «Вернуться», раз в 20 с) не должен
// останавливать идущий опрос своей же комнаты. Настоящая функция
// попробоватьВернуться вырезается из js/сеть.js и гоняется в песочнице.
// Запуск: node tests/тихий-возврат-не-останавливает-опрос.js
// Ломающий запуск: node tests/тихий-возврат-не-останавливает-опрос.js --сломать
//   (портит КОПИЮ сети во временной папке, файл проекта не трогает).
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const vm = require('node:vm');

const ПУТЬ_СЕТИ = path.join(__dirname, '..', 'js', 'сеть.js');
const НАЧАЛО_ФУНКЦИИ = '  function попробоватьВернуться(';

// Вырезает функцию из исходника; ноль найденного — провал, а не падение.
function вырезатьФункцию(исходник) {
  const начало = исходник.indexOf(НАЧАЛО_ФУНКЦИИ);
  if (начало === -1) throw new Error('в сети не найдена функция попробоватьВернуться');
  const конец = исходник.indexOf('\n  /**', начало);
  const кусок = исходник.slice(начало, конец === -1 ? undefined : конец);
  if (!кусок.trim()) throw new Error('вырезанный кусок функции пуст');
  return кусок;
}

// Один случай. Возвращает null, если всё хорошо, иначе — слова о провале.
async function случай(функция, { тихо, опросИдёт, таЖеКомната, долженСпрашивать }) {
  let запросов = 0, ответ = null, ответыло = false;
  const среда = {
    поколение: 12,
    // Игрок не выходил из комнаты — «/выйти» никуда не летит.
    выходВПути: null,
    опросИдёт, код: 'AAAA', пропуск: 'test-token', СПОР_АДРЕСОВ_ЖДЁТ: 1,
    вспомнитьКомнату: () => ({ код: таЖеКомната ? 'AAAA' : 'BBBB', пропуск: 'test-token' }),
    бедаАдреса: () => false, адресСервера: () => 'http://localhost',
    комнатуДержитДругаяВкладка: () => false, сказать: () => {},
    забытьКомнату: () => {},
    итогОтказа: (вид) => ({ вид }),
    послеВыхода: (_к, дальше) => дальше(),
    новоеПоколение: () => ++среда.поколение,
    ответУстарел: n => n !== среда.поколение,
    стукВДверь: async () => { запросов++; return { итог: 'сервер-игры', комнат: 1 }; },
    спроситьПроКомнату: (_с, _п, _сообщить, _тихо, готово) => готово(true),
    готово: жива => { ответыло = true; ответ = жива; }
  };
  vm.createContext(среда);
  try {
    vm.runInContext(функция + '\nпопробоватьВернуться(false, ' + тихо + ', готово);', среда);
  } catch (e) {
    return 'функция упала: ' + e.message;
  }
  await new Promise(resolve => setImmediate(resolve));
  if (!ответыло) return 'плашка не получила ответа (наИтог не вызван)';
  if (ответ !== true) return 'ответ «' + ответ + '» вместо «партия жива»';
  if (запросов !== (долженСпрашивать ? 1 : 0)) {
    return 'сервер спросили ' + запросов + ' раз, ждали ' + (долженСпрашивать ? 1 : 0);
  }
  // Тихая проверка поколений не заводит никогда; явный возврат — заводит одно.
  const ждалиПоколение = (долженСпрашивать && !тихо) ? 13 : 12;
  if (среда.поколение !== ждалиПоколение) {
    return 'поколение стало ' + среда.поколение + ', ждали ' + ждалиПоколение +
      ' (идущий опрос стал бы «устаревшим»)';
  }
  return null;
}

const СЛУЧАИ = [
  ['тихо, опрос этой комнаты идёт — сервер не спрашивают, поколение не меняется',
    { тихо: true, опросИдёт: true, таЖеКомната: true, долженСпрашивать: false }],
  ['тихо, опрос остановлен — спрашивают сервер, поколение не меняется',
    { тихо: true, опросИдёт: false, таЖеКомната: true, долженСпрашивать: true }],
  ['тихо, опрос идёт, но сохранена другая комната — спрашивают сервер',
    { тихо: true, опросИдёт: true, таЖеКомната: false, долженСпрашивать: true }],
  ['явный возврат (не тихо) при идущем опросе — спрашивают сервер, новое поколение',
    { тихо: false, опросИдёт: true, таЖеКомната: true, долженСпрашивать: true }]
];

async function прогнать(путьСети) {
  const итоги = [];
  let функция;
  try {
    функция = вырезатьФункцию(fs.readFileSync(путьСети, 'utf8'));
  } catch (e) {
    return СЛУЧАИ.map(([имя]) => ({ имя, беда: e.message }));
  }
  for (const [имя, доводы] of СЛУЧАИ) {
    итоги.push({ имя, беда: await случай(функция, доводы) });
  }
  return итоги;
}

// Поломки копии: [что портим, что искать (ровно один раз), чем заменить, какой случай должен покраснеть]
const ПОЛОМКИ = [
  ['тихая проверка перестала узнавать идущий опрос', 'if (тихо && опросИдёт && код === сохранённое.код',
    'if (false && тихо && опросИдёт && код === сохранённое.код', 0],
  ['тихая проверка заводит новое поколение', 'const моё = тихо ? поколение : новоеПоколение();',
    'const моё = новоеПоколение();', 1],
  ['«идущий опрос» считается и для чужой комнаты', 'опросИдёт && код === сохранённое.код &&',
    'опросИдёт &&', 2],
  ['явный возврат тоже пропускается при идущем опросе', 'if (тихо && опросИдёт && код',
    'if (опросИдёт && код', 3]
];

(async () => {
  const аргументы = process.argv.slice(2);
  const довод = аргументы.find(а => а.startsWith('--сеть='));
  if (!аргументы.includes('--сломать')) {
    const итоги = await прогнать(довод ? довод.slice(7) : ПУТЬ_СЕТИ);
    let провалов = 0;
    for (const { имя, беда } of итоги) {
      if (беда) { провалов++; console.log('ПРОВАЛ  ' + имя + ' — ' + беда); }
      else console.log('ок      ' + имя);
    }
    console.log('Итого проверок: ' + итоги.length + ', провалов: ' + провалов);
    process.exit(провалов ? 1 : 0);
  }
  // Ломающий запуск: каждая порча — в своей копии, во временной папке.
  const исходник = fs.readFileSync(ПУТЬ_СЕТИ, 'utf8');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'тихий-возврат-'));
  let покраснело = 0, негодных = 0;
  for (let i = 0; i < ПОЛОМКИ.length; i++) {
    const [что, искать, заменить, номерСлучая] = ПОЛОМКИ[i];
    const раз = исходник.split(искать).length - 1;
    if (раз !== 1) {
      негодных++;
      console.log('ПРОВАЛ  поломку «' + что + '» не применить: строка порчи найдена ' + раз + ' раз, нужно ровно 1');
      continue;
    }
    const копия = path.join(папка, 'сеть-' + i + '.js');
    fs.writeFileSync(копия, исходник.replace(искать, () => заменить));
    const итоги = await прогнать(копия);
    if (итоги[номерСлучая].беда) {
      покраснело++;
      console.log('покраснела  ' + что + ' → ' + итоги[номерСлучая].беда);
    } else {
      негодных++;
      console.log('НЕ ПОКРАСНЕЛА  ' + что);
    }
  }
  console.log('Поломок: ' + ПОЛОМКИ.length + ', покраснело: ' + покраснело);
  console.log('Копии лежат в ' + папка);
  process.exit(покраснело === ПОЛОМКИ.length && !негодных ? 0 : 1);
})().catch(e => { console.error(e); process.exit(1); });
