const fs = require('fs');
const os = require('os');
const path = require('path');
const http = require('http');
const { chromium, подготовитьПодделку } = require('./браузер-робот.js');

const ПОРТ = Number(process.argv[2]) || 8080;
const СЛОМАТЬ = process.argv.includes('--сломать');
const КОРЕНЬ = path.join(__dirname, '..');
const АДРЕС = 'http://127.0.0.1:' + ПОРТ + '/шашки.html';

let всегоПроверок = 0;
let провалов = 0;
function проверить(условие, слова) {
  всегоПроверок++;
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}
const спать = (мс) => new Promise((готово) => setTimeout(готово, мс));

/** Тап по клетке доски по имени поля («c3», «d4»…) — как в остальных стендах шашек. */
async function тапПоПолю(страница, поле) {
  await страница.evaluate((имя) => {
    const узел = document.querySelector('[data-поле="' + имя + '"]');
    if (узел) узел.click();
  }, поле);
}

/**
 * «следитьЗаКонсолью» выключаем для ломающей копии: она нарочно неполная
 * (нет звуков, части картинок) и честно сыплет своими 404 — это шум
 * раздачи, а не то, что проверяет этот тест. За настоящими JS-падениями
 * (pageerror) следим всегда, в обоих режимах.
 */
async function новаяСтраница(браузер, следитьЗаКонсолью) {
  const окно = await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
  const страница = await окно.newPage();
  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  if (следитьЗаКонсолью !== false) {
    страница.on('console', (м) => {
      if (м.type() !== 'error') return;
      // Подделка блокирует настоящий telegram-web-app.js (см. браузер-робот.js,
      // безTelegram) — сама блокировка иногда всплывает console-ошибкой про
      // этот адрес. Это шум подделки, не поломка проверяемого кода.
      const откуда = (м.location && м.location() && м.location().url) || '';
      if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
      красные.push('консоль: ' + м.text());
    });
  }
  await подготовитьПодделку(страница, { версия: '8.0' });
  return { окно, страница, красные };
}

/**
 * Сам сценарий жалобы: вдвоём на одном телефоне, тап по пустой клетке
 * без выбранной шашки, затем тап по чужой (чёрной) шашке.
 * «Ноль найденных узлов» на доске — это провал проверки, а не пропуск:
 * доска устроена по-другому — тест обязан сказать об этом громко.
 */
async function прогонПроверок(страница, метка) {
  await страница.click('#лобби-вдвоём');
  await спать(300);

  const пустая = await страница.evaluate(() => {
    const свободные = Array.from(document.querySelectorAll('#доска .поле[data-поле]'))
      .filter((п) => !п.querySelector('.фишка'));
    // Предпочитаем клетку из середины доски (ряды 4–5) — ровно то место,
    // о котором говорит жалоба, а не крайнюю горизонталь у своих фишек.
    const средние = свободные.filter((п) => /[45]$/.test(п.getAttribute('data-поле')));
    const цель = средние[0] || свободные[0];
    return цель ? цель.getAttribute('data-поле') : null;
  });
  if (пустая === null) {
    проверить(false, метка + ': на доске нашлась хоть одна пустая игровая клетка — устройство доски проверить не удалось');
    return;
  }
  await тапПоПолю(страница, пустая);
  await спать(150);
  const текст1 = await страница.evaluate(() => document.getElementById('строка-хода').textContent);
  console.log('  ' + метка + ': тап по пустой клетке «' + пустая + '» → «' + текст1 + '»');
  проверить(/Выберите/.test(текст1),
    метка + ': строка состояния зовёт выбрать шашку (содержит «Выберите»), а пришло «' + текст1 + '»');

  const чужая = await страница.evaluate(() => {
    const фишка = document.querySelector('#доска .фишка--чёрная');
    const клетка = фишка ? фишка.closest('.поле[data-поле]') : null;
    return клетка ? клетка.getAttribute('data-поле') : null;
  });
  if (чужая === null) {
    проверить(false, метка + ': на доске нашлась хоть одна чёрная (чужая для первого хода) шашка');
    return;
  }
  await тапПоПолю(страница, чужая);
  await спать(150);
  const текст2 = await страница.evaluate(() => document.getElementById('строка-хода').textContent);
  console.log('  ' + метка + ': тап по чужой шашке «' + чужая + '» → «' + текст2 + '»');
  проверить(/ход/i.test(текст2),
    метка + ': строка состояния объясняет про ход (содержит «ход»), а пришло «' + текст2 + '»');
}

/* ---------------------------------------------------------------------
   ЛОМАЮЩИЙ ЗАПУСК: своя копия проекта во временной папке, в ней
   испорчена ровно строка подсказки «Выберите свою шашку» — та же
   проверка выше обязана на ней провалиться. Настоящий файл проекта
   эта функция не открывает на запись вовсе.
   --------------------------------------------------------------------- */
const ТИПЫ_ФАЙЛОВ = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.svg': 'image/svg+xml'
};

function подготовитьСломаннуюКопию() {
  const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'шашки-подсказки-'));
  fs.copyFileSync(path.join(КОРЕНЬ, 'шашки.html'), path.join(врем, 'шашки.html'));
  for (const имя of ['style.css', 'style-коллекция.css', 'style-шашки.css']) {
    fs.copyFileSync(path.join(КОРЕНЬ, имя), path.join(врем, имя));
  }
  fs.cpSync(path.join(КОРЕНЬ, 'js'), path.join(врем, 'js'), { recursive: true });
  fs.cpSync(path.join(КОРЕНЬ, 'img', 'шашки'), path.join(врем, 'img', 'шашки'), { recursive: true });

  const путьЭкрана = path.join(врем, 'js', 'шашки-экран.js');
  const исходник = fs.readFileSync(путьЭкрана, 'utf8');
  const строка = "if (приВыборе) return 'Выберите свою шашку';";
  if (исходник.indexOf(строка) === -1) {
    console.log('ОШИБКА: в копии js/шашки-экран.js не нашлась строка «' + строка + '» —');
    console.log('приём порчи устарел (текст подсказки поменялся), этот тест надо обновить.');
    process.exit(1);
  }
  fs.writeFileSync(путьЭкрана,
    исходник.split(строка).join("/* порчено --сломать: подсказки при выборе шашки нет */ return 'Сюда пойти нельзя';"),
    'utf8');
  return врем;
}

function поднятьРаздачу(корень) {
  const сервер = http.createServer(function (запрос, ответ) {
    let путь = запрос.url.split('?')[0].split('#')[0];
    try { путь = decodeURIComponent(путь); } catch (ошибка) { /* оставим как есть */ }
    const файл = path.join(корень, путь === '/' ? 'шашки.html' : путь.slice(1));
    if (файл.indexOf(корень) !== 0) { ответ.writeHead(403); ответ.end('нельзя'); return; }
    fs.readFile(файл, function (беда, тело) {
      if (беда) { ответ.writeHead(404); ответ.end('нет такого файла'); return; }
      ответ.writeHead(200, { 'Content-Type': ТИПЫ_ФАЙЛОВ[path.extname(файл).toLowerCase()] || 'text/plain' });
      ответ.end(тело);
    });
  });
  return new Promise((готово) => сервер.listen(0, '127.0.0.1', () => готово(сервер)));
}

(async () => {
  console.log('Шашки — подсказки при недопустимом тапе. Страница: ' + АДРЕС);
  const браузер = await chromium.launch();

  console.log('\n=== 1. Основной прогон: пустая клетка → «Выберите», чужая шашка → «ход» ===');
  {
    const { окно, страница, красные } = await новаяСтраница(браузер);
    await страница.goto(АДРЕС);
    await спать(400);
    await прогонПроверок(страница, 'основной');
    проверить(красные.length === 0, 'основной: консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));
    await окно.close();
  }

  if (СЛОМАТЬ) {
    console.log('\n=== 2. Ломающий запуск: своя копия без подсказки, своя раздача — обязан провалиться ===');
    const врем = подготовитьСломаннуюКопию();
    const сервер = await поднятьРаздачу(врем);
    const порт = сервер.address().port;
    console.log('  копия: ' + врем + ', раздача на порту ' + порт);
    const { окно, страница, красные } = await новаяСтраница(браузер, false);
    await страница.goto('http://127.0.0.1:' + порт + '/шашки.html');
    await спать(400);
    await прогонПроверок(страница, '(--сломать, ждём провал)');
    проверить(красные.length === 0, '(--сломать) страница не падала по-настоящему (pageerror)' +
      (красные.length ? ': ' + красные.join(' | ') : ''));
    await окно.close();
    await new Promise((готово) => сервер.close(готово));
    fs.rmSync(врем, { recursive: true, force: true });   // убираем СВОЮ копию, не файл проекта
  }

  await браузер.close();
  if (СЛОМАТЬ) {
    console.log('\n=== ИТОГ ЛОМАЮЩЕГО ЗАПУСКА (обязан быть с провалами) ===');
  } else {
    console.log('\n=== ИТОГ ОСНОВНЫХ ПРОВЕРОК ===');
  }
  console.log('Итого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
})().catch((о) => { console.error('Стенд упал: ' + (о && о.stack || о)); process.exit(2); });
