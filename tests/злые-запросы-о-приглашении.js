/* =====================================================================
   ЗЛЫЕ ЗАПРОСЫ О ПРИГЛАШЕНИИ ДРУГА.

   Что это за дверь. В игре появилась кнопка «Позвать друга»: игра
   отправляет серверу свою подпись от Telegram и готовую ссылку, а сервер
   просит Telegram подготовить сообщение с этой ссылкой. Дверь называется
   /приглашение.

   Чем она опасна. Через неё сервер РАЗГОВАРИВАЕТ С TELEGRAM ОТ ИМЕНИ
   НАШЕГО БОТА. Значит, если её обмануть, посторонний сможет:
     — разослать сообщение от имени чужого игрока (подменив, кто просит);
     — вложить в сообщение свою ссылку и сделать нашего бота почтальоном
       для чего угодно;
     — дёргать Telegram без остановки нашим токеном.
   Поэтому здесь всё и проверяется со стороны злоумышленника.

   ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ: настоящего токена бота. Файл bot/.env
   не читается ни разу. Разбор подписи проверяется на ВЫДУМАННОМ токене —
   сервер нарочно отдаёт наружу отдельную функцию «ктоПодписал», которой
   токен передают доводом (см. server/сервер.js). Поэтому проверка ничего
   не знает про секрет и никуда его не отправляет.

   Из этого следует честное ограничение, о котором надо сказать вслух:
   ВЕРНУЮ ПОДПИСЬ ЧЕРЕЗ НАСТОЯЩУЮ ДВЕРЬ здесь не проверить — чтобы её
   сделать, нужен настоящий токен. Через дверь проверяется только то, что
   она правильно ОТКАЗЫВАЕТ и не роняет сервер. А что она правильно
   пропускает — проверяется на функции разбора подписи с выдуманным
   токеном, отдельно.

   Запуск:
       node tests/злые-запросы-о-приглашении.js
       node tests/злые-запросы-о-приглашении.js 8795   (свой порт)

   Выход 0 — провалов нет, 1 — есть.
   ===================================================================== */

