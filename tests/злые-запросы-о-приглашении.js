/* =====================================================================
   ЧАСТЬ 3. Сама дверь по HTTP

   Здесь проверяется только то, что дверь правильно ОТКАЗЫВАЕТ, ничего
   лишнего не рассказывает и не роняет сервер. Верную подпись сюда
   не подать: для неё нужен настоящий токен, а его проверка не трогает.
   ===================================================================== */

function спросить(путь, тело) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(typeof тело === 'string' ? тело : JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН_АДРЕС, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (ч) { текст += ч; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (е) { разобрано = null; }
        готово({ код: ответ.statusCode, тело: разобрано, текст: текст });
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

