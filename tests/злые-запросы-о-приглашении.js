const ТОКЕН_ДЛЯ_ПРОБЫ = '1234567:VYDUMANNYY-TOKEN-DLYA-PROVERKI-podpisi';
const ДРУГОЙ_ТОКЕН = '7654321:SOVSEM-DRUGOY-TOKEN-dlya-sravneniya-XYZ';

