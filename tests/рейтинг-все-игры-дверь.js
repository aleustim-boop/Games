async function сценарий1_ВсеИгрыДаютСумму(порт) {
  console.log('\n1. Игра="все" дает СУММУ очков/побед/партий по всем играм, не максимум');
  const ответ = await рейтингИгрока(порт, ОСНОВНОЙ, 'Основной', 'все');

  проверить(ответ.номер === 200, 'статус 200 (было: ' + ответ.номер + ')');
  проверить(ответ.данные && ответ.данные.ок === true, 'ок=true');
  проверить(ответ.данные && ответ.данные.узналиВас === true, 'узналиВас=true');
  проверить(ответ.данные && ответ.данные.игра === 'все', 'поле игра="все" (было: ' + (ответ.данные && ответ.данные.игра) + ')');

  /* ОСНОВНОЙ: 2 партии в дураке (1 победа + 1 поражение) +
                 1 партия в шашках (1 поражение) +
                 1 партия в го (1 победа)
     Итого: 4 партии, 2 победы, 2 поражения. */
  if (ответ.данные && ответ.данные.я) {
    проверить(typeof ответ.данные.я.партий === 'number' && ответ.данные.я.партий === 4,
      'сумма партий у ОСНОВНОГО = 4 (все игры), было: ' + ответ.данные.я.партий);
    проверить(typeof ответ.данные.я.побед === 'number' && ответ.данные.я.побед === 2,
      'сумма побед у ОСНОВНОГО = 2 (все игры), было: ' + ответ.данные.я.побед);
  } else {
    проверить(false, 'поле я присутствует в ответе (было: ' + (ответ.данные && ответ.данные.я) + ')');
  }
}

