'use strict';
/* =====================================================================
   СТОЛ ДУРАКА: ПРАВКИ РЕВЬЮЕРА 1, 2, 4, 6 — на живой странице.

   Ревьюер нашёл на новом столе (11 сентября) четыре беды; разработчик
   починил и написал эту проверку, тестировщик перенёс её в tests/.

     1. Веер соперника: была одна карта, стало семь — рубашки не должны
        лечь стопкой (число карт оформлению сообщается до замера).
        Здесь же ломающий прогон: число после замера — рубашки стопкой.
     4. Достоинства в отказе — буквами с карт («7 или J»), а не «7 или В».
     6. Появился итог — лист «Ещё» стола закрылся.
     2. Партия кончилась, пока человек читал «Как играть», — итог поверх
        правил не лёг, а после «Назад» он на месте вместе с «Играть ещё».

   Запуск (страничный сервер уже поднят):
       node tests/стол-правки-ревьюера.js            (страницы на 8080)
       node tests/стол-правки-ревьюера.js 8141
   ===================================================================== */
const path = require('path');
const { chromium, подготовитьПодделку } = require(path.join(__dirname, 'браузер-робот.js'));
const АДРЕС = 'http://127.0.0.1:' + (process.argv[2] || '8080') + '/';

let провалов = 0;
function надо(условие, слова) { console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова); if (!условие) провалов++; }

(async () => {
  const браузер = await chromium.launch();
  const страница = await (await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true })).newPage();
  const красные = [];
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const где = (м.location && м.location() && м.location().url) || '';
    if (!/telegram-web-app\.js/.test(где)) красные.push(м.text());
  });
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  await подготовитьПодделку(страница, { версия: '8.0', полныйЭкран: 'дают' });
  await страница.goto(АДРЕС);
  await страница.waitForFunction(() => typeof настройкиИгрыСБотами !== 'undefined');
  await страница.waitForTimeout(400);
  await страница.click('#кнопка-игра-дурак');
  await страница.waitForTimeout(250);
  await страница.evaluate(() => { настройкиИгрыСБотами.игроков = 2; настройкиИгрыСБотами.парами = false; });
  await страница.click('#кнопка-режим-бот');
  await страница.waitForTimeout(1500);

  // 1. Веер соперника: была одна карта, стало семь — рубашки не стопкой.
  function разбросВеера() {
    const лево = [...document.querySelectorAll('#карты-бота > .карта')].map((к) => parseFloat(к.style.left) || 0);
    return { карт: лево.length, разных: new Set(лево.map(Math.round)).size, размах: Math.round(Math.max(...лево) - Math.min(...лево)) };
  }
  const веер = await страница.evaluate((разброс) => {
    const было = партия.руки.бот.slice();
    партия.руки.бот = было.slice(0, 1);
    перерисовать();
    партия.руки.бот = [было[0], было[0], было[0], было[0], было[0], было[0], было[0]];
    перерисовать();
    const после = eval('(' + разброс + ')')();
    // Ломающий прогон: одна карта снова, потом семь — но число карт оформлению
    // пишем, как раньше, ПОСЛЕ замера. Рубашки обязаны лечь стопкой.
    партия.руки.бот = было.slice(0, 1);
    перерисовать();
    const настоящая = отметитьМестаВВеере;
    отметитьМестаВВеере = function () {};
    партия.руки.бот = [было[0], было[0], было[0], было[0], было[0], было[0], было[0]];
    перерисовать();
    const поСтарому = eval('(' + разброс + ')')();
    отметитьМестаВВеере = настоящая;
    партия.руки.бот = было;
    перерисовать();
    return { после, поСтарому, ширина: getComputedStyle(document.getElementById('карты-бота')).width };
  }, разбросВеера.toString());
  console.log('1. веер: ' + JSON.stringify(веер));
  надо(веер.после.карт === 7 && веер.после.разных === 7 && веер.после.размах > 40,
    'одна карта → семь: все семь рубашек разложены (размах ' + веер.после.размах + ')');
  надо(веер.поСтарому.размах < веер.после.размах,
    'ломающий прогон виден: число после замера даёт размах ' + веер.поСтарому.размах + ' против ' + веер.после.размах);

  // 4. Достоинства в отказе — буквами с карт.
  const список = await страница.evaluate(() => {
    const стол = партия.стол;
    партия.стол = [{ атака: { масть: '♠', имя: '7' }, защита: { масть: '♠', имя: 'В' } }];
    const ответ = достоинстваСписком();
    партия.стол = стол;
    return ответ;
  });
  надо(список === '7 или J', 'достоинства на столе словами: «' + список + '»');

  // 6. Появился итог — лист «Ещё» закрылся.
  const лист = await страница.evaluate(() => {
    открытьЛистИгры();
    const открыт = листИгрыОткрыт();
    показатьПлашкуИтога();
    const после = листИгрыОткрыт();
    const итог = document.getElementById('экран-результата');
    итог.classList.remove('экран--виден', 'экран--поверх');
    return { открыт, после };
  });
  надо(лист.открыт && !лист.после, 'итог закрывает лист «Ещё»: ' + JSON.stringify(лист));

  // 2. Партия кончилась, пока человек читал «Как играть», — после «Назад» итог на месте.
  const видимый = () => [...document.querySelectorAll('.экран.экран--виден')].map((э) => э.id).join(',');
  console.log('   перед листом видно: ' + await страница.evaluate(видимый));
  await страница.evaluate(() => { открытьЛистИгры(); });
  await страница.click('#кнопка-лист-игры-правила');
  await страница.waitForTimeout(300);
  console.log('   после «Как играть» видно: ' + await страница.evaluate(видимый));
  await страница.evaluate(() => {
    // Партия кончилась за спиной: так её заканчивает игра — итог засчитан,
    // показ плашки отложен. Отложенный показ застаёт человека на правилах.
    партия.завершена = true;
    партия.результат = 'бот';
    партия.проигравшие = ['бот'];
    отменитьПоказИтога();
    таймерИтога = setTimeout(показатьРезультат, 50);
  });
  await страница.waitForTimeout(300);
  console.log('   после конца партии видно: ' + await страница.evaluate(видимый));
  const наПравилах = await страница.evaluate(() => document.getElementById('экран-результата').classList.contains('экран--виден'));
  // В Telegram «Назад» — его стрелка; она зовёт ровно это.
  await страница.evaluate(() => шагНазадСоЭкрана('экран-правил'));
  await страница.waitForTimeout(400);
  const итог = await страница.evaluate(() => ({
    видно: document.getElementById('экран-результата').classList.contains('экран--виден'),
    заголовок: document.getElementById('текст-результата').textContent,
    ещё: !document.getElementById('кнопка-ещё').classList.contains('скрыт')
  }));
  надо(!наПравилах, 'пока человек на правилах, итог поверх правил не лёг');
  надо(итог.видно && итог.ещё, 'после «Назад» к столу итог показан, «Играть ещё» на месте: ' + JSON.stringify(итог));

  надо(красные.length === 0, 'консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));
  await браузер.close();
  console.log('Итог: провалов ' + провалов);
  process.exit(провалов ? 1 : 0);
})().catch((о) => { console.error('проверка упала: ' + (о && о.stack || о)); process.exit(2); });
