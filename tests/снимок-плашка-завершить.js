  проверить(метка + ': плашка легла ПОВЕРХ листа «⋯» (точка заголовка листа теперь внутри плашки)',
    Boolean(данные.поверхЗаголовка) && данные.поверхЗаголовка.найден === true && данные.поверхЗаголовка.внутриПлашки === true,
    JSON.stringify(данные.поверхЗаголовка));
