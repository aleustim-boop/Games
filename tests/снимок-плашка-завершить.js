const НАЧАЛО_БЛОКА = '/* ---------- Плашка «Завершить партию?» ----------';
const КОНЕЦ_БЛОКА = '/* ---------- «Что было» — лист снизу ----------';

function создатьИспорченныйCSS() {
  const оригинал = fs.readFileSync(ПУТЬ_СТИЛЯ, 'utf8');
  const начало = оригинал.indexOf(НАЧАЛО_БЛОКА);
  const конец = оригинал.indexOf(КОНЕЦ_БЛОКА);
  if (начало === -1 || конец === -1 || конец <= начало) {
    throw new Error('ломающий запуск сломался: в style.css не нашлись метки блока «Плашка «Завершить партию?»» ' +
      '(начало=' + начало + ', конец=' + конец + ') — портить нечего. Похоже, блок переименовали, ' +
      'переставили или удалили комментарии-заголовки — поправьте маркеры НАЧАЛО_БЛОКА/КОНЕЦ_БЛОКА вслед за ним.');
  }
  return оригинал.slice(0, начало) + оригинал.slice(конец);
}

/* ---------------------------------------------------------------------
   Надёжный снимок — декодер PNG и повтор при подозрительно тёмном кадре.
   Перенесено (скопировано, не через require) из tests/обход-игр.js,
   который сам когда-то перенёс это из tests/обход-рейтинга.js — тот же
   приём, тот же порядок действий, менять логику незачем.
   --------------------------------------------------------------------- */
const ПОРОГ_МАКС_ЯРКОСТИ = 200;
const ПОПЫТОК_СНИМКА_МАКС = 4;

function decodePNG(буфер) {
  if (буфер.length < 8 || буфер.readUInt32BE(0) !== 0x89504e47) throw new Error('не похоже на PNG (нет сигнатуры)');
  let смещение = 8;
  let ширина = 0, высота = 0, битГлубина = 0, типЦвета = 0;
  const idatЧасти = [];
  while (смещение + 8 <= буфер.length) {
    const длина = буфер.readUInt32BE(смещение);
    const тип = буфер.toString('ascii', смещение + 4, смещение + 8);
    const данные = буфер.subarray(смещение + 8, смещение + 8 + длина);
    if (тип === 'IHDR') {
      ширина = данные.readUInt32BE(0); высота = данные.readUInt32BE(4);
      битГлубина = данные.readUInt8(8); типЦвета = данные.readUInt8(9);
    } else if (тип === 'IDAT') {
      idatЧасти.push(данные);
    } else if (тип === 'IEND') {
      break;
    }
    смещение += 8 + длина + 4;
  }
  if (битГлубина !== 8) throw new Error('ожидался PNG с 8 битами на канал, получено ' + битГлубина);
  const каналов = { 0: 1, 2: 3, 4: 2, 6: 4 }[типЦвета];
  if (!каналов) throw new Error('неподдержанный тип цвета PNG: ' + типЦвета);
  const сырые = zlib.inflateSync(Buffer.concat(idatЧасти));
  const байтСтроки = ширина * каналов;
  const пиксели = Buffer.alloc(высота * байтСтроки);
  let вход = 0;
  let предыдущаяСтрока = Buffer.alloc(байтСтроки);
  for (let y = 0; y < высота; y++) {
    const типФильтра = сырые[вход]; вход++;
    const строка = сырые.subarray(вход, вход + байтСтроки);
    вход += байтСтроки;
    const результат = Buffer.alloc(байтСтроки);
    for (let x = 0; x < байтСтроки; x++) {
      const raw = строка[x];
      const a = x >= каналов ? результат[x - каналов] : 0;
      const b = предыдущаяСтрока[x];
      const c = x >= каналов ? предыдущаяСтрока[x - каналов] : 0;
      let значение;
      if (типФильтра === 0) значение = raw;
      else if (типФильтра === 1) значение = raw + a;
      else if (типФильтра === 2) значение = raw + b;
      else if (типФильтра === 3) значение = raw + Math.floor((a + b) / 2);
      else if (типФильтра === 4) {
        const p = a + b - c;
        const pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c);
        значение = raw + (pa <= pb && pa <= pc ? a : (pb <= pc ? b : c));
      } else throw new Error('неизвестный тип фильтра строки PNG: ' + типФильтра);
      результат[x] = значение & 0xff;
    }
    результат.copy(пиксели, y * байтСтроки);
    предыдущаяСтрока = результат;
  }
  return { ширина: ширина, высота: высота, каналов: каналов, пиксели: пиксели };
}

function яркостьСнимка(буфер) {
  const { ширина, высота, каналов, пиксели } = decodePNG(буфер);
  const шаг = 3;
  let макс = 0;
  for (let y = 0; y < высота; y += шаг) {
    for (let x = 0; x < ширина; x += шаг) {
      const idx = (y * ширина + x) * каналов;
      const яркость = 0.299 * пиксели[idx] + 0.587 * пиксели[idx + 1] + 0.114 * пиксели[idx + 2];
      if (яркость > макс) макс = яркость;
    }
  }
  return { максЯркость: макс };
}

async function снятьСнимокНадёжно(страница) {
  let буфер = null, метрика = { максЯркость: 0 }, ошибкаРазбора = null;
  for (let попытка = 1; попытка <= ПОПЫТОК_СНИМКА_МАКС; попытка++) {
    await страница.evaluate(() => new Promise((готово) => requestAnimationFrame(() => requestAnimationFrame(готово))));
    буфер = await страница.screenshot();
    try {
      метрика = яркостьСнимка(буфер);
      ошибкаРазбора = null;
    } catch (е) {
      ошибкаРазбора = е;
      break;
    }
    if (метрика.максЯркость >= ПОРОГ_МАКС_ЯРКОСТИ) return { буфер, метрика, попыток: попытка, ошибкаРазбора: null };
    await страница.waitForTimeout(250 * попытка);
  }
  return { буфер, метрика, попыток: ПОПЫТОК_СНИМКА_МАКС, ошибкаРазбора };
}

function собратьОшибки(страница) {
  const ошибки = [];
  страница.on('pageerror', (о) => ошибки.push('исключение: ' + о.message));
  страница.on('console', (с) => {
    if (с.type() !== 'error') return;
    if (/Failed to load resource/.test(с.text())) return;
    ошибки.push('консоль: ' + с.text());
  });
  return ошибки;
}

