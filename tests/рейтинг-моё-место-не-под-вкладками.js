/* =====================================================================
   ПРОВЕРКА: КАРТОЧКА «МОЁ МЕСТО» НЕ ЗАЕЗЖАЕТ ПОД НИЖНЮЮ ПАНЕЛЬ ВКЛАДОК.

   Замысел владельца (коммит 07ed072, 25.09, style.css): карточка «Моё
   место» идёт ПОСЛЕ всего списка обычным потоком (не «sticky») и не
   закрывает его последнюю строку. При коротком списке карточка может
   оказаться ниже края окна, пока список не прокручен, — это нормально
   и здесь не проверяется. Проверяем то, что владелец запретил: список
   прокручен до конца, и —
     (а) нижний край карточки не ниже верхнего края полосы вкладок;
     (б) карточка не перекрывает последнюю строку таблицы;
     (в) карточка НЕ «position: sticky» (решение владельца — обычный поток).

   Сценарий — «Дурак — все игроки» (тот же, что вскрыл беду и живёт в
   tests/обход-рейтинга.js): открыть рейтинг, настоящим кликом
   переключиться на игру «Дурак» (кнопка выбора игры → панель → пункт
   «Дурак»), список из восьми игроков (пятеро в верхушке, я — на седьмом
   месте среди «вокругМеня») — с таким списком экран не помещается без
   прокрутки на всех проверяемых ширинах.

   ПРИЁМ — тот же, что в tests/обход-рейтинга.js: свой временный http-сервер
   страниц на свободном порту (не 8790/8791/8080 — боевой сервер комнат и
   постоянный стенд), один перехват page.route на дверь /рейтинг и три
   фоновых двери (/статистика, /пульс, /мой-аватар — два отдельных route()
   ломают друг друга, см. шапку tests/браузер-робот.js), и на «/style.css»,
   когда прогон ломающий (см. ниже).

   ДВА РЕЖИМА ЗАПУСКА.
     Обычный:  node tests/рейтинг-моё-место-не-под-вкладками.js
     Ломающий: node tests/рейтинг-моё-место-не-под-вкладками.js --стиль=<путь>
   «--стиль=<путь>» — путь к ЧУЖОЙ копии style.css (готовится снаружи, во
   временной папке — файл проекта не трогается), подставляется на дверь
   «/style.css» ТЕМ ЖЕ обработчиком page.route, что и остальные перехваты.
   Два подготовленных ломающих случая:
     - копия БЕЗ правки исполнителя из style.css (только восстановленный
       блок владельца, без снятия задвоенного зазора таблица→карточка) —
       красная по пункту (а) на 768;
     - копия БЕЗ восстановленного блока владельца целиком — красная по
       пункту (в): без него карточка снова «position: sticky».
   ===================================================================== */

