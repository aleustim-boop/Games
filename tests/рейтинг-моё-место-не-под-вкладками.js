/* ---------------------------------------------------------------------
   Замер после прокрутки списка в конец: карточка, полоса вкладок и
   последняя строка таблицы (не считая строки-шапки).
   --------------------------------------------------------------------- */

async function прокрутитьЭкранВКонецИЗамерить(страница) {
  return страница.evaluate(() => {
    const экран = document.getElementById('экран-рейтинга-игроков');
    if (экран) экран.scrollTop = экран.scrollHeight;

    const карточка = document.getElementById('рейтинг-моё-место');
    const панель = экран ? экран.querySelector('.нижние-вкладки') : document.querySelector('.нижние-вкладки');
    const строки = document.querySelectorAll('#рейтинг-таблица .рейтинг-строка:not(.рейтинг-строка--шапка)');
    const последняяСтрока = строки.length ? строки[строки.length - 1] : null;

    const р = {
      карточкаЕсть: Boolean(карточка),
      панельЕсть: Boolean(панель),
      последняяСтрокаЕсть: Boolean(последняяСтрока)
    };
    if (карточка) {
      const rect = карточка.getBoundingClientRect();
      р.карточка = { top: rect.top, bottom: rect.bottom };
      р.карточкаPosition = getComputedStyle(карточка).position;
    }
    if (панель) {
      const rect = панель.getBoundingClientRect();
      р.панель = { top: rect.top, bottom: rect.bottom };
    }
    if (последняяСтрока) {
      const rect = последняяСтрока.getBoundingClientRect();
      р.последняяСтрока = { top: rect.top, bottom: rect.bottom };
    }
    return р;
  });
}

/* ---------------------------------------------------------------------
   Замер СРАЗУ после открытия, без прокрутки (беда 26.09 на 1280): так
   экран видит игрок первым делом. Только прямоугольники getBoundingClientRect —
   elementFromPoint здесь врёт: центр карточки закрыт полосой, и он
   возвращает полосу (на этом tests/обход-рейтинга.js беду и проглядел).
   «Видимая часть» карточки — её пересечение с областью прокрутки экрана
   (клиентская область «#экран-рейтинга-игроков»): что за краем прокрутки,
   игрок не видит, и полоса это закрыть не может.
   --------------------------------------------------------------------- */

async function замеритьБезПрокрутки(страница) {
  return страница.evaluate(() => {
    const экран = document.getElementById('экран-рейтинга-игроков');
    const карточка = document.getElementById('рейтинг-моё-место');
    const панель = экран ? экран.querySelector('.нижние-вкладки') : null;
    const р = {
      экранЕсть: Boolean(экран), карточкаЕсть: Boolean(карточка), панельЕсть: Boolean(панель),
      высотаОкна: window.innerHeight
    };
    if (экран) {
      const rect = экран.getBoundingClientRect();
      // Клиентская область: без рамки, без полосы прокрутки.
      р.прокрутка = экран.scrollTop;
      р.область = { top: rect.top + экран.clientTop, bottom: rect.top + экран.clientTop + экран.clientHeight };
      р.экран = { видно: экран.clientHeight, всего: экран.scrollHeight };
    }
    if (карточка) {
      const rect = карточка.getBoundingClientRect();
      р.карточка = { top: rect.top, bottom: rect.bottom };
    }
    if (панель) {
      const rect = панель.getBoundingClientRect();
      р.панель = { top: rect.top, bottom: rect.bottom };
    }
    return р;
  });
}

/** Ни один видимый пиксель карточки не лежит под полосой вкладок. */
function сверитьБезПрокрутки(метка, замер) {
  if (!замер.экранЕсть || !замер.карточкаЕсть || !замер.панельЕсть) {
    return проверить(метка, 'без прокрутки: экран, карточка и полоса найдены', false,
      'экран=' + замер.экранЕсть + ', карточка=' + замер.карточкаЕсть + ', полоса=' + замер.панельЕсть);
  }
  if (замер.прокрутка !== 0) {
    return проверить(метка, 'без прокрутки: экран и правда не прокручен', false, 'scrollTop=' + замер.прокрутка);
  }
  const ЗАЗОР = 0.5; // допуск на субпиксельное округление
  const видноСверху = Math.max(замер.карточка.top, замер.область.top);
  const видноСнизу = Math.min(замер.карточка.bottom, замер.область.bottom);
  const естьВидимое = видноСнизу > видноСверху + ЗАЗОР;
  // Под полосой — всё, что ниже её верха; видимая часть обязана кончаться выше.
  return проверить(метка, 'без прокрутки: видимая часть карточки не под полосой',
    !естьВидимое || видноСнизу <= замер.панель.top + ЗАЗОР,
    'карточка ' + Math.round(замер.карточка.top) + '–' + Math.round(замер.карточка.bottom) +
    ', область прокрутки ' + Math.round(замер.область.top) + '–' + Math.round(замер.область.bottom) +
    ', верх полосы=' + Math.round(замер.панель.top) + ', окно=' + замер.высотаОкна +
    ', экран видно/всего=' + замер.экран.видно + '/' + замер.экран.всего);
}

/* ---------------------------------------------------------------------
   Перебор (задание штаба 26.09): ширины 390, 768, 1280; высоты окна от
   600 до 1100 с шагом 50; списки «8 игроков» и «длинный». На каждое
   сочетание — свежая страница: открыть рейтинг, выбрать «Дурак», сразу
   замерить. Снимки 1280×1000 и 768×900 (8 игроков) — в tests/снимки/.
   --------------------------------------------------------------------- */

const ПЕРЕБОР_ШИРИНЫ = [390, 768, 1280];
const ПЕРЕБОР_ВЫСОТЫ = [];
for (let в = 600; в <= 1100; в += 50) ПЕРЕБОР_ВЫСОТЫ.push(в);
const ПЕРЕБОР_СПИСКИ = [
  { имя: '8 игроков', ответ: ответРейтинга },
  { имя: 'длинный', ответ: ответДлинногоРейтинга }
];
const ПЕРЕБОР_СНИМКИ = { '1280×1000': 'рейтинг-моё-место-1280x1000.png', '768×900': 'рейтинг-моё-место-768x900.png' };

async function переборВысот(браузер, адрес) {
  for (const список of ПЕРЕБОР_СПИСКИ) {
    for (const ширина of ПЕРЕБОР_ШИРИНЫ) {
      for (const высота of ПЕРЕБОР_ВЫСОТЫ) {
        const метка = ширина + '×' + высота + ' (' + список.имя + ')';
        const контекст = await браузер.newContext({ viewport: { width: ширина, height: высота }, hasTouch: ширина < 700 });
        const страница = await контекст.newPage();
        try {
          if (!await открытьРейтингДурака(страница, метка, адрес, список.ответ)) continue;
          const замер = await замеритьБезПрокрутки(страница);
          const имяСнимка = ПЕРЕБОР_СНИМКИ[ширина + '×' + высота];
          if (имяСнимка && список.ответ === ответРейтинга) {
            fs.mkdirSync(ПАПКА_СНИМКОВ, { recursive: true });
            fs.writeFileSync(path.join(ПАПКА_СНИМКОВ, имяСнимка), await страница.screenshot());
          }
          сверитьБезПрокрутки(метка, замер);
        } catch (ошибка) {
          проверить(метка, 'перебор не упал', false, ошибка && ошибка.message || String(ошибка));
        } finally {
          await контекст.close().catch(() => null);
        }
      }
    }
  }
}

/** Три проверки замысла владельца — вызывается один раз, после прокрутки в конец. */
function сверитьЗамер(ширина, замер) {
  if (!проверить(ширина, 'карточка «Моё место» найдена (#рейтинг-моё-место)', замер.карточкаЕсть)) return;
  if (!проверить(ширина, 'полоса вкладок найдена (.нижние-вкладки)', замер.панельЕсть)) return;
  проверить(ширина, 'последняя строка таблицы найдена (#рейтинг-таблица .рейтинг-строка)', замер.последняяСтрокаЕсть);

  const ЗАЗОР = 0.5; // допуск на субпиксельное округление getBoundingClientRect

  // (а) нижний край карточки не ниже верхнего края полосы вкладок
  проверить(ширина, '(а) низ карточки не ниже верха полосы вкладок',
    замер.карточка.bottom <= замер.панель.top + ЗАЗОР,
    'низ карточки=' + Math.round(замер.карточка.bottom) + ', верх панели=' + Math.round(замер.панель.top));

  // (б) карточка не перекрывает последнюю строку таблицы
  if (замер.последняяСтрокаЕсть) {
    проверить(ширина, '(б) карточка не перекрывает последнюю строку таблицы',
      замер.карточка.top >= замер.последняяСтрока.bottom - ЗАЗОР,
      'верх карточки=' + Math.round(замер.карточка.top) + ', низ последней строки=' + Math.round(замер.последняяСтрока.bottom));
  }

  // (в) карточка не «position: sticky» — решение владельца, обычный поток
  проверить(ширина, '(в) карточка не «position: sticky»',
    замер.карточкаPosition !== 'sticky',
    'position=' + замер.карточкаPosition);
}

/**
 * Открывает рейтинг настоящими кликами и переключает на «Дурак».
 * ответ — функция (игра) → тело ответа двери /рейтинг.
 * Возвращает true, если дошли до списка; иначе провал уже записан.
 */
async function открытьРейтингДурака(страница, метка, адрес, ответ) {
  await подготовитьПодделку(страница, { версия: '8.0' });

  // ОДИН обработчик page.route на дверь /рейтинг, три фоновых двери
  // (см. шапку файла) и — только в ломающем прогоне — на «/style.css».
  await перехватить(страница, new RegExp('/(?:рейтинг(?:\\?|$)|статистика(?:\\?|$)|пульс(?:\\?|$)|мой-аватар(?:\\?|$)|style\\.css(?:\\?|$))'),
    function (путь, запрос, адресЗапроса) {
      if (/\/style\.css(?:\?|$)/.test(адресЗапроса || '')) {
        if (стильПодмена !== null) {
          путь.fulfill({ status: 200, contentType: 'text/css; charset=utf-8', body: стильПодмена });
        } else {
          путь.continue();
        }
        return;
      }
      if (!/\/рейтинг(?:\?|$)/.test(адресЗапроса || '')) {
        путь.fulfill({ status: 200, contentType: 'application/json; charset=utf-8', body: JSON.stringify({ ок: false }) });
        return;
      }
      путь.fulfill({ status: 200, contentType: 'application/json; charset=utf-8', body: JSON.stringify(ответ('дурак')) });
    });

  await страница.goto(адрес + '/index.html?сервер=' + АДРЕС_ИГРЫ_ВЫДУМАННЫЙ);
  await страница.waitForTimeout(600);

  if (!await узелЕсть(страница, метка, '#кнопка-вкладка-профиль', 'кнопка «Рейтинг» в нижней панели')) return false;
  if (!await кликНеЗависая(страница, метка, '#кнопка-вкладка-профиль', 'кнопка «Рейтинг» в нижней панели')) return false;
  const экранПоявился = await страница.waitForSelector('#экран-рейтинга-игроков.экран--виден', { timeout: ТАЙМАУТ_ДЕЙСТВИЯ }).catch(() => null);
  if (!проверить(метка, 'экран рейтинга открылся после клика по кнопке', Boolean(экранПоявился))) return false;
  await страница.waitForTimeout(700);

  // Настоящим кликом переключаемся на игру «Дурак» — тот самый сценарий,
  // на котором вскрылась беда (обход-рейтинга.js, «дурак-все-игроки»).
  if (!await узелЕсть(страница, метка, '#рейтинг-выбор-игры-кнопка', 'кнопка выбора игры')) return false;
  if (!await кликНеЗависая(страница, метка, '#рейтинг-выбор-игры-кнопка', 'кнопка выбора игры')) return false;
  const панельОткрылась = await страница.waitForSelector('#рейтинг-панель-игр:not(.скрыт)', { timeout: ТАЙМАУТ_ДЕЙСТВИЯ }).catch(() => null);
  if (!проверить(метка, 'панель выбора игры открылась после клика', Boolean(панельОткрылась))) return false;
  if (!await узелЕсть(страница, метка, '#рейтинг-панель-игр-пункт-дурак', 'пункт «Дурак» в панели игр')) return false;
  if (!await кликНеЗависая(страница, метка, '#рейтинг-панель-игр-пункт-дурак', 'пункт «Дурак»')) return false;
  await страница.waitForTimeout(700);
  return true;
}

async function прогонШирины(браузер, ширина, адрес) {
  const высота = ширина < 700 ? 844 : 1000;
  const контекст = await браузер.newContext({ viewport: { width: ширина, height: высота }, hasTouch: ширина < 700 });
  const страница = await контекст.newPage();

  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const т = м.text();
    // Обрыв настоящего telegram-web-app.js (его режет подделка нарочно,
    // см. tests/браузер-робот.js) в тексте сообщения адреса не содержит —
    // «Failed to load resource» без URL. Смотрим ещё и место ошибки.
    const откуда = (м.location() && м.location().url) || '';
    if (/telegram-web-app\.js|telegram\.org/.test(т) || /telegram-web-app\.js|telegram\.org/.test(откуда)) return;
    красные.push('консоль: ' + т + (откуда ? ' (' + откуда + ')' : ''));
  });

  try {
    if (!await открытьРейтингДурака(страница, ширина, адрес, ответРейтинга)) return;

    // Список — до конца, дальше меряем замысел владельца: (а), (б), (в).
    const замер = await прокрутитьЭкранВКонецИЗамерить(страница);
    await страница.waitForTimeout(150);

    if (ширина === 768) {
      fs.mkdirSync(ПАПКА_СНИМКОВ, { recursive: true });
      const буфер = await страница.screenshot();
      fs.writeFileSync(path.join(ПАПКА_СНИМКОВ, 'рейтинг-моё-место-768.png'), буфер);
    }

    сверитьЗамер(ширина, замер);

    if (красные.length) {
      красные.forEach((стр) => проверить(ширина, 'ошибки в консоли отсутствуют', false, стр));
    } else {
      проверить(ширина, 'ошибок в консоли нет', true);
    }
  } catch (ошибка) {
    проверок++; провалов++;
    const строка = 'ПЛОХО — ' + ширина + ': проверка упала — ' + (ошибка && ошибка.message || ошибка);
    console.log(строка);
    находки.push(строка);
  } finally {
    await контекст.close().catch(() => null);
  }
}

