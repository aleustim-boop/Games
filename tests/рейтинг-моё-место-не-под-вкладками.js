(async () => {
  const ШИРИНЫ = [320, 390, 768, 1280];

  console.log(стильПодмена === null
    ? '=== Моё место / вкладки: ОБЫЧНЫЙ прогон ===\n'
    : '=== Моё место / вкладки: ЛОМАЮЩИЙ прогон (--стиль=' + доводСтиля.slice('--стиль='.length) + ') ===\n');

  const порт = await выбратьСвободныйПорт();
  const сервер = await поднятьСервер(порт);
  const адрес = 'http://' + АДРЕС_ХОЗЯИНА + ':' + порт;
  console.log('Свой временный сервер страниц: ' + адрес + '\n');

  const браузер = await chromium.launch();
  try {
    for (const ширина of ШИРИНЫ) {
      await прогонШирины(браузер, ширина, адрес);
    }
  } finally {
    await браузер.close().catch(() => null);
    await new Promise((готово) => сервер.close(готово));
  }

  console.log('');
  console.log('Снимок 768 — ' + path.join(ПАПКА_СНИМКОВ, 'рейтинг-моё-место-768.png'));
  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
  process.exit(провалов > 0 ? 1 : 0);
})().catch((ошибка) => {
  console.error('Проверка «Моё место / вкладки» упала: ' + (ошибка && ошибка.stack || ошибка));
  process.exit(2);
});
