/* ---------------------------------------------------------------------
   Клики без зависания — понятный провал вместо голого Timeout 30000ms.
   --------------------------------------------------------------------- */

async function узелЕсть(страница, ширина, селектор, описание) {
  const найден = await страница.$(селектор).catch(() => null);
  return проверить(ширина, 'узел «' + описание + '» найден (' + селектор + ')', Boolean(найден));
}

async function кликНеЗависая(страница, ширина, селектор, описание) {
  try {
    await страница.click(селектор, { timeout: ТАЙМАУТ_ДЕЙСТВИЯ });
    return true;
  } catch (ошибка) {
    проверить(ширина, 'клик по «' + описание + '» удался (' + селектор + ')', false,
      'не дождался: ' + (ошибка && ошибка.message ? ошибка.message.split('\n')[0] : ошибка));
    return false;
  }
}

/* ---------------------------------------------------------------------
   Замер после прокрутки списка в конец: карточка, полоса вкладок и
   последняя строка таблицы (не считая строки-шапки).
   --------------------------------------------------------------------- */

async function прокрутитьЭкранВКонецИЗамерить(страница) {
  return страница.evaluate(() => {
    const экран = document.getElementById('экран-рейтинга-игроков');
    if (экран) экран.scrollTop = экран.scrollHeight;

    const карточка = document.getElementById('рейтинг-моё-место');
    const панель = экран ? экран.querySelector('.нижние-вкладки') : document.querySelector('.нижние-вкладки');
    const строки = document.querySelectorAll('#рейтинг-таблица .рейтинг-строка:not(.рейтинг-строка--шапка)');
    const последняяСтрока = строки.length ? строки[строки.length - 1] : null;

    const р = {
      карточкаЕсть: Boolean(карточка),
      панельЕсть: Boolean(панель),
      последняяСтрокаЕсть: Boolean(последняяСтрока)
    };
    if (карточка) {
      const rect = карточка.getBoundingClientRect();
      р.карточка = { top: rect.top, bottom: rect.bottom };
      р.карточкаPosition = getComputedStyle(карточка).position;
    }
    if (панель) {
      const rect = панель.getBoundingClientRect();
      р.панель = { top: rect.top, bottom: rect.bottom };
    }
    if (последняяСтрока) {
      const rect = последняяСтрока.getBoundingClientRect();
      р.последняяСтрока = { top: rect.top, bottom: rect.bottom };
    }
    return р;
  });
}

/** Три проверки замысла владельца — вызывается один раз, после прокрутки в конец. */
function сверитьЗамер(ширина, замер) {
  if (!проверить(ширина, 'карточка «Моё место» найдена (#рейтинг-моё-место)', замер.карточкаЕсть)) return;
  if (!проверить(ширина, 'полоса вкладок найдена (.нижние-вкладки)', замер.панельЕсть)) return;
  проверить(ширина, 'последняя строка таблицы найдена (#рейтинг-таблица .рейтинг-строка)', замер.последняяСтрокаЕсть);

  const ЗАЗОР = 0.5; // допуск на субпиксельное округление getBoundingClientRect

  // (а) нижний край карточки не ниже верхнего края полосы вкладок
  проверить(ширина, '(а) низ карточки не ниже верха полосы вкладок',
    замер.карточка.bottom <= замер.панель.top + ЗАЗОР,
    'низ карточки=' + Math.round(замер.карточка.bottom) + ', верх панели=' + Math.round(замер.панель.top));

  // (б) карточка не перекрывает последнюю строку таблицы
  if (замер.последняяСтрокаЕсть) {
    проверить(ширина, '(б) карточка не перекрывает последнюю строку таблицы',
      замер.карточка.top >= замер.последняяСтрока.bottom - ЗАЗОР,
      'верх карточки=' + Math.round(замер.карточка.top) + ', низ последней строки=' + Math.round(замер.последняяСтрока.bottom));
  }

  // (в) карточка не «position: sticky» — решение владельца, обычный поток
  проверить(ширина, '(в) карточка не «position: sticky»',
    замер.карточкаPosition !== 'sticky',
    'position=' + замер.карточкаPosition);
}

async function прогонШирины(браузер, ширина, адрес) {
  const высота = ширина < 700 ? 844 : 1000;
  const контекст = await браузер.newContext({ viewport: { width: ширина, height: высота }, hasTouch: ширина < 700 });
  const страница = await контекст.newPage();

  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const т = м.text();
    // Обрыв настоящего telegram-web-app.js (его режет подделка нарочно,
    // см. tests/браузер-робот.js) в тексте сообщения адреса не содержит —
    // «Failed to load resource» без URL. Смотрим ещё и место ошибки.
    const откуда = (м.location() && м.location().url) || '';
    if (/telegram-web-app\.js|telegram\.org/.test(т) || /telegram-web-app\.js|telegram\.org/.test(откуда)) return;
    красные.push('консоль: ' + т + (откуда ? ' (' + откуда + ')' : ''));
  });

  try {
    await подготовитьПодделку(страница, { версия: '8.0' });

    // ОДИН обработчик page.route на дверь /рейтинг, три фоновых двери
    // (см. шапку файла) и — только в ломающем прогоне — на «/style.css».
    await перехватить(страница, new RegExp('/(?:рейтинг(?:\\?|$)|статистика(?:\\?|$)|пульс(?:\\?|$)|мой-аватар(?:\\?|$)|style\\.css(?:\\?|$))'),
      function (путь, запрос, адресЗапроса) {
        if (/\/style\.css(?:\?|$)/.test(адресЗапроса || '')) {
          if (стильПодмена !== null) {
            путь.fulfill({ status: 200, contentType: 'text/css; charset=utf-8', body: стильПодмена });
          } else {
            путь.continue();
          }
          return;
        }
        if (!/\/рейтинг(?:\?|$)/.test(адресЗапроса || '')) {
          путь.fulfill({ status: 200, contentType: 'application/json; charset=utf-8', body: JSON.stringify({ ок: false }) });
          return;
        }
        путь.fulfill({ status: 200, contentType: 'application/json; charset=utf-8', body: JSON.stringify(ответРейтинга('дурак')) });
      });

    await страница.goto(адрес + '/index.html?сервер=' + АДРЕС_ИГРЫ_ВЫДУМАННЫЙ);
    await страница.waitForTimeout(600);

    if (!await узелЕсть(страница, ширина, '#кнопка-вкладка-профиль', 'кнопка «Рейтинг» в нижней панели')) return;
    if (!await кликНеЗависая(страница, ширина, '#кнопка-вкладка-профиль', 'кнопка «Рейтинг» в нижней панели')) return;
    const экранПоявился = await страница.waitForSelector('#экран-рейтинга-игроков.экран--виден', { timeout: ТАЙМАУТ_ДЕЙСТВИЯ }).catch(() => null);
    if (!проверить(ширина, 'экран рейтинга открылся после клика по кнопке', Boolean(экранПоявился))) return;
    await страница.waitForTimeout(700);

    // Настоящим кликом переключаемся на игру «Дурак» — тот самый сценарий,
    // на котором вскрылась беда (обход-рейтинга.js, «дурак-все-игроки»).
    if (!await узелЕсть(страница, ширина, '#рейтинг-выбор-игры-кнопка', 'кнопка выбора игры')) return;
    if (!await кликНеЗависая(страница, ширина, '#рейтинг-выбор-игры-кнопка', 'кнопка выбора игры')) return;
    const панельОткрылась = await страница.waitForSelector('#рейтинг-панель-игр:not(.скрыт)', { timeout: ТАЙМАУТ_ДЕЙСТВИЯ }).catch(() => null);
    if (!проверить(ширина, 'панель выбора игры открылась после клика', Boolean(панельОткрылась))) return;
    if (!await узелЕсть(страница, ширина, '#рейтинг-панель-игр-пункт-дурак', 'пункт «Дурак» в панели игр')) return;
    if (!await кликНеЗависая(страница, ширина, '#рейтинг-панель-игр-пункт-дурак', 'пункт «Дурак»')) return;
    await страница.waitForTimeout(700);

    // Список — до конца, дальше меряем замысел владельца: (а), (б), (в).
    const замер = await прокрутитьЭкранВКонецИЗамерить(страница);
    await страница.waitForTimeout(150);

    if (ширина === 768) {
      fs.mkdirSync(ПАПКА_СНИМКОВ, { recursive: true });
      const буфер = await страница.screenshot();
      fs.writeFileSync(path.join(ПАПКА_СНИМКОВ, 'рейтинг-моё-место-768.png'), буфер);
    }

    сверитьЗамер(ширина, замер);

    if (красные.length) {
      красные.forEach((стр) => проверить(ширина, 'ошибки в консоли отсутствуют', false, стр));
    } else {
      проверить(ширина, 'ошибок в консоли нет', true);
    }
  } catch (ошибка) {
    проверок++; провалов++;
    const строка = 'ПЛОХО — ' + ширина + ': проверка упала — ' + (ошибка && ошибка.message || ошибка);
    console.log(строка);
    находки.push(строка);
  } finally {
    await контекст.close().catch(() => null);
  }
}

