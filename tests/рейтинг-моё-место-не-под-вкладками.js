function свободныйПорт() {
  return new Promise((готово, брак) => {
    const проба = http.createServer();
    проба.on('error', брак);
    проба.listen(0, АДРЕС_ХОЗЯИНА, () => {
      const порт = проба.address().port;
      проба.close(() => готово(порт));
    });
  });
}

async function выбратьСвободныйПорт() {
  for (let попытка = 0; попытка < 6; попытка++) {
    const порт = await свободныйПорт();
    if (ЗАПРЕЩЁННЫЕ_ПОРТЫ.indexOf(порт) === -1) return порт;
  }
  throw new Error('не удалось получить свободный порт, отличный от боевых 8790/8791 и от стенда 8080');
}

const ТИПЫ_ФАЙЛОВ = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.woff2': 'font/woff2'
};

/** Секреты и служебные файлы — свой сервер их не раздаёт ни при каких условиях. */
function запрещённыйАдрес(адрес) {
  const низ = адрес.toLowerCase();
  if (низ.indexOf('.env') !== -1) return true;
  const части = низ.split(/[\\/]/).filter(Boolean);
  if (части.length && части[0] === 'bot') return true;
  return части.some((часть) => часть.charAt(0) === '.');
}

function поднятьСервер(порт) {
  return new Promise((готово) => {
    const сервер = http.createServer((запрос, ответ) => {
      let адрес;
      try {
        адрес = decodeURIComponent(запрос.url.split('?')[0]);
      } catch (ошибка) {
        ответ.writeHead(400); ответ.end('непонятный адрес'); return;
      }
      if (адрес === '/') адрес = '/index.html';
      if (запрещённыйАдрес(адрес)) { ответ.writeHead(403); ответ.end('доступ закрыт'); return; }

      const относительный = адрес.replace(/^\/+/, '');
      const файл = path.join(КОРЕНЬ, относительный);
      if (файл !== КОРЕНЬ && !файл.startsWith(КОРЕНЬ + path.sep)) {
        ответ.writeHead(403); ответ.end('доступ закрыт: файл вне папки проекта'); return;
      }

      fs.readFile(файл, (ошибка, данные) => {
        if (ошибка) { ответ.writeHead(404); ответ.end('не найдено: ' + адрес); return; }
        ответ.writeHead(200, {
          'Content-Type': ТИПЫ_ФАЙЛОВ[path.extname(файл).toLowerCase()] || 'application/octet-stream',
          'Cache-Control': 'no-store'
        });
        ответ.end(данные);
      });
    });
    сервер.listen(порт, АДРЕС_ХОЗЯИНА, () => готово(сервер));
  });
}

