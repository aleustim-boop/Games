/* =====================================================================
   Партия целиком «пальцем»: тапы по подсвеченным клеткам, до итога.

   Проверяем то, ради чего всё и делалось:
     • партия вдвоём за одним телефоном в рекорды НЕ пишется;
     • партия против робота пишется и показывает серию на плашке итога;
     • кнопка «Рекорды» открывает таблицу, «Назад к доске» возвращает;
     • кнопка «← Назад» уводит на index.html.
   ===================================================================== */

const { chromium } = require('./браузер-робот.js');
const ПОРТ = Number(process.argv[2]) || 8080;    // страничный сервер уже поднят
const АДРЕС = 'http://127.0.0.1:' + ПОРТ + '/шашки.html';

let провалов = 0;
function проверить(условие, слова) {
  console.log((условие ? '  ок   — ' : '  ПЛОХО— ') + слова);
  if (!условие) провалов++;
}

/** Один тап: поднять шашку или пойти на подсвеченное поле. Возвращает «сходили ли». */
async function тапнуть(страница) {
  return страница.evaluate(() => {
    const случайный = (список) => список[Math.floor(Math.random() * список.length)];
    const куда = document.querySelectorAll('.поле--можно, .поле--можно-бой');
    if (куда.length > 0) { случайный(Array.from(куда)).click(); return 'ход'; }
    const свои = document.querySelectorAll('.фишка--может-ходить');
    if (свои.length > 0) { случайный(Array.from(свои)).parentElement.click(); return 'поднял'; }
    return 'нечего';
  });
}

async function доигратьДоКонца(страница, пределТапов) {
  for (let i = 0; i < пределТапов; i++) {
    const кончено = await страница.evaluate(() =>
      document.getElementById('экран-итога').classList.contains('экран--виден'));
    if (кончено) return i;
    const что = await тапнуть(страница);
    if (что === 'нечего') await страница.waitForTimeout(120);   // думает робот
    else await страница.waitForTimeout(25);
  }
  return -1;
}

(async () => {
  const браузер = await chromium.launch();
  const окно = await браузер.newContext({ viewport: { width: 360, height: 640 }, hasTouch: true });
  const страница = await окно.newPage();
  const ошибки = [];
  страница.on('pageerror', (о) => ошибки.push('исключение: ' + о.message));
  страница.on('console', (с) => { if (с.type() === 'error') ошибки.push('консоль: ' + с.text()); });
  await страница.goto(АДРЕС);
  await страница.waitForTimeout(300);

  console.log('\n=== 1. Партия вдвоём за одним телефоном ===');
  /* Страница открывается на экране «с кем играть» (он появился вместе
     с тремя входами: бот, вдвоём, онлайн). Раньше доска показывалась
     сразу, и стенд начинал тапать по ней — теперь до доски надо дойти. */
  await страница.click('#кнопка-вдвоём');
  await страница.waitForTimeout(300);
  const тапов1 = await доигратьДоКонца(страница, 900);
  проверить(тапов1 >= 0, 'партия доиграна до итога, тапов: ' + тапов1);
  const после1 = await страница.evaluate(() => ({
    заголовок: document.getElementById('заголовок-итога').textContent,
    причина: document.getElementById('причина-итога').textContent,
    серияВидна: !document.getElementById('серия-шашек').classList.contains('скрыт'),
    записано: window.localStorage.getItem('rating_shashki')
  }));
  console.log('  итог: «' + после1.заголовок + '» — ' + после1.причина);
  проверить(после1.записано === null, 'партия вдвоём в рекорды не записана');
  проверить(!после1.серияВидна, 'строки про серию на плашке нет — считать её не с кого');

  console.log('\n=== 2. Партия против робота (лёгкий) ===');
  /* С плашки итога уходим кнопкой «Другой соперник» — она убирает плашку
     и открывает экран «с кем играть». Дальше уровень бота живёт на своём
     экране, поэтому сначала «Играть с ботом», и только там «Лёгкий». */
  await страница.click('#кнопка-другой-соперник');
  await страница.waitForTimeout(300);
  await страница.click('#кнопка-режим-бот');
  await страница.waitForTimeout(300);
  await страница.click('#уровень-лёгкий');
  await страница.click('#кнопка-с-ботом');
  await страница.waitForTimeout(300);
  const тапов2 = await доигратьДоКонца(страница, 1200);
  проверить(тапов2 >= 0, 'партия с роботом доиграна до итога, тапов: ' + тапов2);
  await страница.waitForTimeout(600);   // хранилище отвечает не мгновенно
  const после2 = await страница.evaluate(() => {
    const запись = window.localStorage.getItem('rating_shashki');
    return {
      заголовок: document.getElementById('заголовок-итога').textContent,
      серия: document.getElementById('серия-шашек').textContent,
      серияВидна: !document.getElementById('серия-шашек').classList.contains('скрыт'),
      запись: запись ? JSON.parse(запись) : null
    };
  });
  console.log('  итог: «' + после2.заголовок + '», строка серии: «' + после2.серия + '»');
  проверить(после2.запись !== null, 'партия с роботом записана в rating_shashki');
  проверить(после2.запись && после2.запись.игра === 'шашки', 'запись помечена игрой «шашки»');
  проверить(после2.запись && после2.запись.всего[0] === 1, 'в записи ровно одна партия: ' +
    (после2.запись ? после2.запись.всего.join('/') : '—'));
  const этоПоражение = /Соперник выиграл/.test(после2.заголовок);
  проверить(этоПоражение ? true : после2.серияВидна,
    'после победы или ничьей строка серии показана' + (этоПоражение ? ' (здесь было поражение)' : ''));

  console.log('\n=== 3. Кнопки рекордов и выхода ===');
  await страница.click('#кнопка-рекорды-итог');
  await страница.waitForTimeout(400);
  проверить(await страница.evaluate(() => window.ШашкиРекорды.открыты()), 'кнопка на плашке открыла рекорды');
  const видно = await страница.evaluate(() => document.getElementById('лучший-рекорд').textContent);
  console.log('  «' + видно + '»');
  await страница.click('#кнопка-рекорды-назад');
  await страница.waitForTimeout(200);
  проверить(await страница.evaluate(() =>
    !window.ШашкиРекорды.открыты() &&
    document.getElementById('экран-шашек').classList.contains('экран--виден')), 'кнопка «Назад к доске» вернула доску');
  проверить(await страница.evaluate(() =>
    document.getElementById('экран-итога').classList.contains('экран--виден')),
    'плашка итога вернулась вместе с доской — партия ведь окончена');

  // Новая партия из-под открытых рекордов: плашка не должна остаться висеть
  await страница.click('#кнопка-ещё');
  await страница.waitForTimeout(200);
  проверить(await страница.evaluate(() =>
    !document.getElementById('экран-итога').classList.contains('экран--виден')),
    'после «Играть ещё» плашка итога убралась');

  await страница.click('#кнопка-рекорды');
  await страница.waitForTimeout(300);
  проверить(await страница.evaluate(() => window.ШашкиРекорды.открыты()), 'кнопка под доской тоже открывает рекорды');
  await страница.click('#кнопка-рекорды-назад');
  await страница.waitForTimeout(200);

  /* Выход стал в два шага: из-под доски «В меню» уводит на экран
     «с кем играть», и уже оттуда «К выбору игры» — на index.html. */
  await страница.click('#кнопка-в-меню-шашки');
  await страница.waitForTimeout(400);
  проверить(await страница.evaluate(() => window.ШашкиРежимы.открыты()),
    'кнопка «В меню» под доской вернула экран «с кем играть»');
  await страница.click('#кнопка-назад');
  await страница.waitForTimeout(600);
  проверить(/index\.html$/.test(страница.url()), 'кнопка «К выбору игры» увела на index.html: ' + страница.url());

  проверить(ошибки.length === 0, 'красных ошибок в консоли нет' +
    (ошибки.length ? ': ' + ошибки.join(' | ') : ''));

  await браузер.close();
  console.log('\n' + (провалов === 0 ? 'ВСЁ ЗЕЛЁНОЕ' : 'ПРОВАЛОВ: ' + провалов));
  process.exit(провалов === 0 ? 0 : 1);
})().catch((о) => { console.error('проверка сломалась:', о); process.exit(2); });
