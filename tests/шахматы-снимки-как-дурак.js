'use strict';

/* =====================================================================
   ШАХМАТЫ КАК ДУРАК: СНИМКИ ДЛЯ СРАВНЕНИЯ ГЛАЗАМИ + ПРОВЕРКА УЗЛОВ.

   Что делает: на ширинах 390 и 320 снимает лобби шахмат и лобби дурака
   (index.html) под теми же размерами, а также плашку итога шахмат после
   победы над ботом. Победу ставим без долгой партии: подменяем одну дверь
   правил (создатьПартию отдаёт позицию «мат в один ход»), дальше ходит
   живой палец и всё считает сам экран. Снимки — в
   tests/снимки/шахматы-как-дурак/ .

   Кроме снимков проверяет узлы: ноль найденного — провал, а не пропуск.
   Ждём в лобби шахмат аватар, рейтинг, место и два входа; в плашке
   итога — «Играть ещё», «Рекорды», «В меню», строку «итог-рейтинга»;
   в лобби дурака — те же аватар, рейтинг, место.

   Запуск (файловый сервер уже поднят, порт свой, не 8790):
       node tests/шахматы-снимки-как-дурак.js 8131
   Ломающий запуск — на КОПИИ проекта во временной папке. Поднять на копии
   свой сервер (КОРЕНЬ_СЕРВЕРА=<копия> node tests/локальный-сервер.js <порт>),
   испортить в копии шахматы.html (например убрать id="лобби-аватар"),
   и запустить эту проверку на порт копии — обязана покраснеть:
       node tests/шахматы-снимки-как-дурак.js <порт копии>
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const { chromium, подготовитьПодделку } = require('./браузер-робот.js');

const ПОРТ = Number(process.argv.slice(2).find((а) => /^\d+$/.test(а))) || 8080;
const ОСНОВА = 'http://127.0.0.1:' + ПОРТ + '/';
const ПАПКА = path.join(__dirname, 'снимки', 'шахматы-как-дурак');
// Мат в один ход: белый ферзь b1 -> b8, чёрный король h8 заперт королём g6.
const ПОЗИЦИЯ = '7k/8/6K1/8/8/8/8/1Q6 w - - 0 1';

let всего = 0;
let провалов = 0;
function проверить(условие, слова) {
  всего++;
  console.log((условие ? '  ок      ' : '  ПРОВАЛ  ') + слова);
  if (!условие) провалов++;
}
const спать = (мс) => new Promise((ф) => setTimeout(ф, мс));

async function открыть(браузер, ширина, высота, страницаФайл, сПозицией) {
  const окно = await браузер.newContext({ viewport: { width: ширина, height: высота }, hasTouch: true, deviceScaleFactor: 2 });
  const страница = await окно.newPage();
  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
    if (/Failed to load resource/.test(м.text())) return;
    красные.push('консоль: ' + м.text());
  });
  await подготовитьПодделку(страница, { версия: '8.0' });
  if (сПозицией) {
    await страница.addInitScript((фен) => {
      let настоящие = null;
      Object.defineProperty(window, 'ШахматыПравила', {
        configurable: true,
        get() { return настоящие; },
        set(значение) {
          настоящие = значение;
          if (значение && typeof значение.партияИзFEN === 'function') {
            const былоСоздать = значение.создатьПартию;
            значение.создатьПартию = function () {
              try { return значение.партияИзFEN(фен); } catch (сбой) { return былоСоздать.apply(this, arguments); }
            };
          }
        }
      });
    }, ПОЗИЦИЯ);
  }
  await страница.goto(ОСНОВА + страницаФайл);
  await спать(700);
  return { окно, страница, красные };
}

/** Узел найден и виден: размер больше нуля. */
async function виден(страница, селектор) {
  return страница.evaluate((с) => {
    const у = document.querySelector(с);
    if (!у) return { есть: false, виден: false };
    const р = у.getBoundingClientRect();
    return { есть: true, виден: р.width > 0 && р.height > 0 && у.offsetParent !== null };
  }, селектор);
}

async function нужныеУзлы(страница, метка, селекторы) {
  for (const [имя, селектор] of селекторы) {
    const р = await виден(страница, селектор);
    проверить(р.есть && р.виден, метка + ': «' + имя + '» (' + селектор + ') найден и виден');
  }
}

/** Узел найден (виден или нет — не важно). Ноль найденного — провал. */
async function нужныеУзлыЕсть(страница, метка, селекторы) {
  for (const [имя, селектор] of селекторы) {
    const р = await виден(страница, селектор);
    проверить(р.есть, метка + ': «' + имя + '» (' + селектор + ') найден');
  }
}

async function снять(страница, имяФайла) {
  const путь = path.join(ПАПКА, имяФайла);
  await страница.screenshot({ path: путь });
  const размер = fs.existsSync(путь) ? fs.statSync(путь).size : 0;
  проверить(размер > 1000, 'снимок записан: tests/снимки/шахматы-как-дурак/' + имяФайла + ' (' + размер + ' байт)');
}

(async () => {
  fs.mkdirSync(ПАПКА, { recursive: true });
  console.log('Шахматы как дурак — снимки. Основа: ' + ОСНОВА);
  const браузер = await chromium.launch();

  for (const [ширина, высота] of [[390, 844], [320, 568]]) {
    console.log('\n=== Ширина ' + ширина + ': лобби шахмат ===');
    {
      const { окно, страница, красные } = await открыть(браузер, ширина, высота, 'шахматы.html', false);
      await нужныеУзлы(страница, 'лобби шахмат ' + ширина, [
        ['аватар', '#экран-лобби #лобби-аватар'],
        ['играть с ботами', '#лобби-боты'],
        ['игра онлайн', '#лобби-найти-игру']
      ]);
      // Рейтинг и место без сети пусты и могут быть скрыты — важно, что узлы есть.
      await нужныеУзлыЕсть(страница, 'лобби шахмат ' + ширина, [
        ['рейтинг', '#экран-лобби #лобби-рейтинг'],
        ['место', '#экран-лобби #лобби-место']
      ]);
      проверить((await страница.$$('#лобби-серия-текст')).length === 0, 'лобби шахмат ' + ширина + ': старой серии «лобби-серия-текст» нет');
      const шире = await страница.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1);
      проверить(!шире, 'лобби шахмат ' + ширина + ': страница не шире окна');
      await снять(страница, 'лобби-шахмат-' + ширина + '.png');
      проверить(красные.length === 0, 'лобби шахмат ' + ширина + ': консоль чистая' + (красные.length ? ' — ' + красные.join(' | ') : ''));
      await окно.close();
    }

    console.log('\n=== Ширина ' + ширина + ': лобби дурака (index.html) ===');
    {
      const { окно, страница, красные } = await открыть(браузер, ширина, высота, 'index.html', false);
      // index.html — витрина; лобби дурака открывается плиткой «Дурак».
      const плитка = await виден(страница, '#кнопка-игра-дурак');
      проверить(плитка.есть && плитка.виден, 'лобби дурака ' + ширина + ': плитка «Дурак» на витрине найдена');
      await страница.evaluate(() => { const п = document.getElementById('кнопка-игра-дурак'); if (п) п.click(); });
      await спать(700);
      await нужныеУзлы(страница, 'лобби дурака ' + ширина, [
        ['аватар', '#экран-лобби #лобби-аватар']
      ]);
      await нужныеУзлыЕсть(страница, 'лобби дурака ' + ширина, [
        ['рейтинг', '#экран-лобби #лобби-рейтинг'],
        ['место', '#экран-лобби #лобби-место']
      ]);
      await снять(страница, 'лобби-дурака-' + ширина + '.png');
      проверить(красные.length === 0, 'лобби дурака ' + ширина + ': консоль чистая' + (красные.length ? ' — ' + красные.join(' | ') : ''));
      await окно.close();
    }

    console.log('\n=== Ширина ' + ширина + ': плашка итога шахмат после победы над ботом ===');
    {
      const { окно, страница, красные } = await открыть(браузер, ширина, высота, 'шахматы.html', true);
      const нажали = await страница.evaluate(() => {
        const к = document.getElementById('лобби-боты');
        if (!к) return false;
        к.click();
        return true;
      });
      проверить(нажали, 'итог ' + ширина + ': карточка «Играть с ботами» нажата');
      await спать(400);
      const начали = await страница.evaluate(() => {
        const к = document.getElementById('лобби-бот-начать');
        if (!к) return false;
        к.click();
        return true;
      });
      проверить(начали, 'итог ' + ширина + ': кнопка «Начать» нажата');
      await спать(700);
      const наДоске = await страница.evaluate(() => document.querySelectorAll('#доска .фигура').length);
      console.log('  экраны видны: ' + (await страница.evaluate(() => Array.from(document.querySelectorAll('.экран--виден')).map((э) => э.id).join(', '))) +
        '; правила: ' + (await страница.evaluate(() => typeof window.ШахматыПравила + '/' + (window.ШахматыПравила && typeof window.ШахматыПравила.партияИзFEN))));
      проверить(наДоске === 3, 'итог ' + ширина + ': позиция «мат в один ход» поставлена, на доске 3 фигуры (вышло ' + наДоске + ')');
      for (const поле of ['b1', 'b8']) {
        await страница.evaluate((имя) => {
          const клетка = document.querySelector('[data-поле="' + имя + '"]');
          if (клетка) клетка.click();
        }, поле);
        await спать(250);
      }
      await спать(900);
      const итог = await страница.evaluate(() => {
        const э = document.getElementById('экран-итога');
        const з = document.getElementById('заголовок-итога');
        return { виден: !!э && э.classList.contains('экран--виден'), заголовок: з ? з.textContent.trim() : '' };
      });
      проверить(итог.виден, 'итог ' + ширина + ': плашка итога появилась после мата (заголовок: «' + итог.заголовок + '»)');
      проверить(/выиграл|победил/i.test(итог.заголовок), 'итог ' + ширина + ': заголовок про победу, а вышло «' + итог.заголовок + '»');
      await нужныеУзлы(страница, 'итог ' + ширина, [
        ['Играть ещё', '#экран-итога #кнопка-ещё'],
        ['Рекорды', '#экран-итога #кнопка-рекорды-итог'],
        ['В меню', '#экран-итога #кнопка-в-меню-итог']
      ]);
      const строка = await виден(страница, '#экран-итога #итог-рейтинга');
      проверить(строка.есть, 'итог ' + ширина + ': строка «итог-рейтинга» есть в плашке (видна сейчас: ' + строка.виден + ')');
      const видимыеКнопки = await страница.evaluate(() =>
        Array.from(document.querySelectorAll('#экран-итога button')).filter((к) => к.offsetParent !== null).map((к) => к.textContent.trim()));
      console.log('  видимые кнопки итога: ' + JSON.stringify(видимыеКнопки));
      await снять(страница, 'итог-победа-над-ботом-' + ширина + '.png');
      проверить(красные.length === 0, 'итог ' + ширина + ': консоль чистая' + (красные.length ? ' — ' + красные.join(' | ') : ''));
      await окно.close();
    }
  }

  await браузер.close();
  console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
})().catch((сбой) => {
  console.log('проверка сломалась: ' + сбой.message);
  process.exit(2);
});
