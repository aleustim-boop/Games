/* =====================================================================
   ВРЁТ ЛИ НАДПИСЬ «Отбивается ваш напарник — этот подход мимо вас».

   ЗАЧЕМ ЭТОТ ФАЙЛ. В игре парами человека законно не зовут по нескольку
   подходов подряд, и отличить это от поломки глазами нельзя. Игра теперь
   сама объясняет человеку, что происходит.

   ЧТО ИЗМЕНИЛОСЬ С ПРОШЛОГО РАЗА. Раньше надпись звучала «Сейчас играет
   пара соперников — ваш ход ещё придёт» — то есть давала ОБЕЩАНИЕ, и файл
   мерил, сдержано ли оно (6% партий кончались поражением сразу после
   обещания). Обещания в тексте больше нет: надпись описывает настоящее.
   Значит и мерить надо другое — ПРАВДУ, а не обещание:
     - правда ли отбивается именно напарник, а не кто-то ещё;
     - правда ли подход идёт мимо человека (он не нападает, не отбивается
       и подкинуть не вправе).

   И ГЛАВНОЕ: УСЛОВИЕ ПОКАЗА БОЛЬШЕ НЕ ПЕРЕСКАЗЫВАЕТСЯ. Прошлая версия
   этого файла держала у себя копию условия своими словами и честно об этом
   предупреждала. Теперь игра отдаёт условие наружу чистой функцией
   «надписьПроНапарникаУместна(партия, подходовМимо, былЯвПодходе)», и файл
   спрашивает её саму. Поправят условие в игре — замер поедет за ним,
   а не соврёт по старой копии.

   Свой счёт файл ведёт только по прошлому — сколько подходов прошло мимо
   человека и играл ли он в этом подходе: в самой партии прошлого не записано.
   Считается это ровно так же, как в игре (см. «следитьЗаПропущеннымиПодходами»).

   ЧТО МЕРЯЕТСЯ:
     - в непарных раскладках надписи быть не должно ни разу;
     - ЗАЖИГАНИЯ НЕ К МЕСТУ: человек в этом же подходе сам нападал
       или отбивался, а игра говорит, что подход мимо него;
     - НАДПИСЬ СОВРАЛА ПРО НАПАРНИКА: отбивается не напарник;
     - НАДПИСЬ СОВРАЛА ПРО «МИМО ВАС»: человеку в этот миг вправе
       положить карту (подкинуть) — значит подход не мимо него;
     - НАПАРНИК НЕ ОТБИВАЕТСЯ, А БЕРЁТ: он уже сказал «беру», идёт
       докидывание. Слово «отбивается» тут неточно — считаем отдельно;
     - МЕЛЬТЕШЕНИЕ: сколько раз за партию надпись зажигается и гаснет.

   Запуск:  node tests/врёт-ли-надпись-про-пару.js
   ===================================================================== */

const путьКИгре = require('path').join(__dirname, '..', 'js', 'game.js');
const правила = require(путьКИгре);

const ПАРТИЙ_НА_СОСТАВ = 500;      // столько партий на каждую раскладку
const ПОТОЛОК_ХОДОВ = 900;

/** Слепок стола — по нему видно, сдвинулась ли партия хоть на шаг. */
function слепок(партия) {
  const вРуках = партия.игроки.map((и) => (партия.руки[и] || []).length).join('/');
  const отбитых = партия.стол.filter((пара) => пара.защита).length;
  return [правила.фаза(партия), партия.стол.length, отбитых, партия.отбой.length,
          партия.колода.length, вРуках, партия.атакует,
          (партия.пасы || []).join(',')].join('|');
}

/**
 * Одна партия до конца с наблюдением за надписью.
 * Возвращает, что случилось с человеком: показывали ли ему надпись,
 * правду ли она говорила, сколько раз мигнула.
 */
function сыгратьИПосмотреть(настройки) {
  const партия = правила.создатьПартию(настройки);
  const итог = {
    зависла: false,
    надписьБыла: false,
    показов: 0,          // сколько раз надпись зажигалась (мельтешение)
    шаговСНадписью: 0,   // сколько шагов подряд она провисела на экране
    надписьГорит: false,
    сноваИгралПослеНадписи: false,   // нападал или отбивался (просто к сведению)
    сноваСловоПослеНадписи: false,
    максПодходовМимо: 0,
    подходов: 0,
    чемКончилось: '',
    показовВСвойПодход: 0,           // показана, когда человек в этом подходе уже играл
    показовКогдаЯНападаю: 0,         // показана прямо под его собственным нападением
    отбивалсяНеНапарник: 0,          // «отбивается ваш напарник» — а отбивается не он
    подходНеМимоМеня: 0,             // «подход мимо вас» — а человеку можно подкинуть
    напарникБерётАНеОтбивается: 0,   // напарник сказал «беру», идёт докидывание
    поФазам: {},                     // на каких фазах надпись висит на экране
    /* «А сколько было бы ДО починки». Прежнее условие не спрашивало двух
       вещей: играл ли человек в этом самом подходе и не в нападающей ли он
       паре. Считаем оба довода отдельно, чтобы видеть, что дала починка. */
    зажиганийПоСтарому: 0,
    горелоПоСтарому: false,
    старыхНеКМесту: 0,
    примерыЛжи: []
  };

  /* Свой счёт прошлого — те же три переменные, что и в игре. */
  let подходовМимоМеня = 0;
  let былЯвЭтомПодходе = false;
  let столБылПустПрошлыйРаз = true;

  for (let ход = 0; ход < ПОТОЛОК_ХОДОВ && !партия.завершена; ход++) {
    const чей = правила.ктоХодит(партия);
    if (!чей) break;
    const было = слепок(партия);
    правила.ходБота(партия, чей);
    if (слепок(партия) === было) { итог.зависла = true; return итог; }

    /* Дальше — ровно то, что делает игра при каждой перерисовке экрана. */
    const столПуст = партия.стол.length === 0;
    const яОтбиваюсь = правила.защищается(партия) === 'человек';
    const мойХод = правила.ктоХодит(партия) === 'человек';
    if (!столПуст && (партия.атакует === 'человек' || яОтбиваюсь)) былЯвЭтомПодходе = true;
    if (столПуст && !столБылПустПрошлыйРаз) {
      итог.подходов++;
      подходовМимоМеня = былЯвЭтомПодходе ? 0 : подходовМимоМеня + 1;
      былЯвЭтомПодходе = false;
    }
    столБылПустПрошлыйРаз = столПуст;
    if (подходовМимоМеня > итог.максПодходовМимо) итог.максПодходовМимо = подходовМимоМеня;

    if (итог.надписьБыла) {
      if (партия.стол.length > 0 && (партия.атакует === 'человек' || яОтбиваюсь)) {
        итог.сноваИгралПослеНадписи = true;
      }
      if (мойХод) итог.сноваСловоПослеНадписи = true;
    }

    /* ВОТ ОНО: условие показа спрашиваем у самой игры, а не у своей копии. */
    const горит = правила.надписьПроНапарникаУместна(партия, подходовМимоМеня, былЯвЭтомПодходе);

    /* А это — то же условие, но КАК БЫЛО ДО ПОЧИНКИ: без двух доводов,
       которые тогда не спрашивали. Мерка нужна ровно затем, чтобы сказать
       штабу, сколько лишних показов убрала правка, а не «стало лучше». */
    const рукаЧ = партия.руки['человек'] || [];
    const горелоБыПоСтарому = Boolean(партия.парами) && !партия.завершена &&
      подходовМимоМеня >= 2 && !мойХод && !яОтбиваюсь && рукаЧ.length > 0;
    if (горелоБыПоСтарому) {
      if (!итог.горелоПоСтарому) итог.зажиганийПоСтарому++;
      if (былЯвЭтомПодходе ||
          (партия.атакует === 'человек' ||
           правила.партнёр(партия, 'человек') === партия.атакует)) {
        итог.старыхНеКМесту++;
      }
    }
    итог.горелоПоСтарому = горелоБыПоСтарому;

    if (горит && !итог.надписьГорит) {
      итог.показов++;
      итог.надписьБыла = true;
    }

    /* ПРАВДУ ПРОВЕРЯЕМ НА КАЖДОМ ШАГЕ, ПОКА НАДПИСЬ ВИСИТ, а не только
       в миг зажигания. Человек читает её всё то время, что она на экране:
       зажечься она может к месту, а через полхода стать неправдой —
       например, напарник скажет «беру» и перестанет отбиваться. */
    if (горит) {
      итог.шаговСНадписью++;

      /* Не к месту: человек в этом самом подходе сам нападал или отбивался,
         а надпись говорит, что подход мимо него. */
      if (былЯвЭтомПодходе) итог.показовВСвойПодход++;
      if (партия.атакует === 'человек' && партия.стол.length > 0) итог.показовКогдаЯНападаю++;

      /* ПРАВДА ЛИ ОТБИВАЕТСЯ НАПАРНИК. Надпись называет его прямо, значит
         имя обязано совпасть с тем, кто отбивается на самом деле. */
      const напарник = правила.партнёр(партия, 'человек');
      const отбивается = правила.защищается(партия);
      if (отбивается !== напарник) {
        итог.отбивалсяНеНапарник++;
        if (итог.примерыЛжи.length < 3) {
          итог.примерыЛжи.push('отбивается «' + отбивается + '», а напарник — «' +
            напарник + '», фаза ' + правила.фаза(партия));
        }
      }

      /* ПРАВДА ЛИ ПОДХОД МИМО. Если человеку прямо сейчас вправе положить
         карту — подход не мимо него, и надпись отговаривает его от хода. */
      if (правила.можетПодкидывать(партия, 'человек') &&
          (правила.фаза(партия) === 'подкидывание' || правила.фаза(партия) === 'докидывание')) {
        итог.подходНеМимоМеня++;
        if (итог.примерыЛжи.length < 3) {
          итог.примерыЛжи.push('сказано «подход мимо вас», а человеку можно подкинуть, фаза ' +
            правила.фаза(партия));
        }
      }

      /* НАПАРНИК УЖЕ ВЗЯЛ. Слово «отбивается» в настоящем времени неточно:
         он сказал «беру» и теперь ждёт, чем его докидают. */
      const ф = правила.фаза(партия);
      итог.поФазам[ф] = (итог.поФазам[ф] || 0) + 1;
      if (ф === 'докидывание') итог.напарникБерётАНеОтбивается++;
    }
    итог.надписьГорит = горит;
  }

  if (!партия.завершена) итог.зависла = true;
  итог.чемКончилось = партия.завершена ? правила.чемКончилосьДляМеня(партия) : '';
  return итог;
}

function проверитьСостав(название, настройки) {
  const свод = {
    партий: 0, зависших: 0, снадписью: 0,
    сноваИграл: 0, толькоСлово: 0, такИНеПозвали: 0,
    мигало: 0, максПоказовЗаПартию: 0, максПодходовМимо: 0,
    показовВсего: 0, шаговСНадписью: 0, показовВСвойПодход: 0, показовКогдаЯНападаю: 0,
    отбивалсяНеНапарник: 0, подходНеМимоМеня: 0, напарникБерёт: 0, партийГдеНапарникВзял: 0,
    зажиганийПоСтарому: 0, старыхНеКМесту: 0,
    поФазам: {},
    партийСПоказомВСвойПодход: 0, партийТолькоНеКМесту: 0,
    примеры: []
  };

  for (let i = 0; i < ПАРТИЙ_НА_СОСТАВ; i++) {
    const итог = сыгратьИПосмотреть(Object.assign({ сложность: 'обычный' }, настройки));
    if (итог.зависла) { свод.зависших++; continue; }
    свод.партий++;
    if (итог.максПодходовМимо > свод.максПодходовМимо) свод.максПодходовМимо = итог.максПодходовМимо;
    свод.зажиганийПоСтарому += итог.зажиганийПоСтарому;
    свод.старыхНеКМесту += итог.старыхНеКМесту;
    if (!итог.надписьБыла) continue;
    свод.снадписью++;
    свод.показовВсего += итог.показов;
    свод.шаговСНадписью += итог.шаговСНадписью;
    свод.показовВСвойПодход += итог.показовВСвойПодход;
    свод.показовКогдаЯНападаю += итог.показовКогдаЯНападаю;
    свод.отбивалсяНеНапарник += итог.отбивалсяНеНапарник;
    свод.подходНеМимоМеня += итог.подходНеМимоМеня;
    свод.напарникБерёт += итог.напарникБерётАНеОтбивается;
    if (итог.напарникБерётАНеОтбивается > 0) свод.партийГдеНапарникВзял++;
    Object.keys(итог.поФазам).forEach(function (ф) {
      свод.поФазам[ф] = (свод.поФазам[ф] || 0) + итог.поФазам[ф];
    });
    if (свод.примеры.length < 5) свод.примеры = свод.примеры.concat(итог.примерыЛжи);
    if (итог.показовВСвойПодход > 0) свод.партийСПоказомВСвойПодход++;
    if (итог.показов > 0 && итог.показовВСвойПодход === итог.показов) свод.партийТолькоНеКМесту++;
    if (итог.показов > свод.максПоказовЗаПартию) свод.максПоказовЗаПартию = итог.показов;
    if (итог.показов > 2) свод.мигало++;
    if (итог.сноваИгралПослеНадписи) свод.сноваИграл++;
    else if (итог.сноваСловоПослеНадписи) свод.толькоСлово++;
    else свод.такИНеПозвали++;
  }

  console.log('--- ' + название + ' ---');
  console.log('  партий доиграно: ' + свод.партий + ', зависших (свойство правил): ' + свод.зависших);
  console.log('  самый долгий обход человека: ' + свод.максПодходовМимо + ' подходов подряд');
  console.log('  надпись показалась в партиях: ' + свод.снадписью +
              ' (' + Math.round(свод.снадписью * 100 / Math.max(1, свод.партий)) + '%)');
  if (свод.снадписью > 0) {
    console.log('    ВСЕГО ЗАЖИГАНИЙ: ' + свод.показовВсего +
                ', а всего шагов игры надпись провисела на экране: ' + свод.шаговСНадписью);
    console.log('    из этих шагов НЕ К МЕСТУ (человек в этом же подходе сам играл): ' +
                свод.показовВСвойПодход + ', в том числе прямо под его собственным нападением: ' +
                свод.показовКогдаЯНападаю);
    console.log('    СОВРАЛА ПРО НАПАРНИКА (отбивается не он): ' + свод.отбивалсяНеНапарник);
    console.log('    СОВРАЛА ПРО «МИМО ВАС» (человеку можно подкинуть): ' + свод.подходНеМимоМеня);
    console.log('    НАПАРНИК НЕ ОТБИВАЕТСЯ, А БЕРЁТ КАРТЫ (он сказал «беру»): ' +
                свод.напарникБерёт + ' шагов из ' + свод.шаговСНадписью +
                ', это ' + Math.round(свод.напарникБерёт * 100 / Math.max(1, свод.шаговСНадписью)) +
                '% времени показа, в партиях: ' + свод.партийГдеНапарникВзял);
    console.log('    на каких фазах надпись висела: ' +
                Object.keys(свод.поФазам).map(function (ф) {
                  return ф + ' — ' + свод.поФазам[ф];
                }).join(', '));
    console.log('    ДЛЯ СРАВНЕНИЯ, как было ДО починки: зажиганий ' + свод.зажиганийПоСтарому +
                ' (сейчас ' + свод.показовВсего + '), из них шагов НЕ К МЕСТУ ' + свод.старыхНеКМесту +
                ' (сейчас ' + свод.показовВСвойПодход + ')');
    console.log('    зажигалась заново больше двух раз за партию (мигание): ' + свод.мигало +
                ', рекорд зажиганий: ' + свод.максПоказовЗаПартию);
    console.log('    партий, где надпись вылезла в свой же подход: ' + свод.партийСПоказомВСвойПодход +
                ', из них таких, где она НИ РАЗУ не попала в дело: ' + свод.партийТолькоНеКМесту);
    console.log('    к сведению — после надписи человек снова нападал или отбивался: ' +
                свод.сноваИграл + ', вернулось только слово: ' + свод.толькоСлово +
                ', так и не позвали до конца партии: ' + свод.такИНеПозвали);
    if (свод.примеры.length > 0) {
      console.log('    примеры неправды: ' + свод.примеры.slice(0, 5).join(' | '));
    }
  }
  console.log('');
  return свод;
}

console.log('=== Врёт ли надпись «Отбивается ваш напарник — этот подход мимо вас» ===');
console.log('Партий на раскладку: ' + ПАРТИЙ_НА_СОСТАВ + '\n');

const составы = [
  ['вдвоём (надписи быть не должно)', { игроков: 2 }],
  ['втроём (надписи быть не должно)', { игроков: 3 }],
  ['вчетвером (надписи быть не должно)', { игроков: 4 }],
  ['вшестером (надписи быть не должно)', { игроков: 6 }],
  ['вчетвером ПАРАМИ', { игроков: 4, парами: true }],
  ['вчетвером ПАРАМИ + перевод', { игроков: 4, парами: true, переводной: true }]
];

let неправдаВсего = 0;
let неКМестуВсего = 0;
let лишняяНадпись = 0;
let миганиеВсего = 0;
for (const [название, настройки] of составы) {
  const свод = проверитьСостав(название, настройки);
  неправдаВсего += свод.отбивалсяНеНапарник + свод.подходНеМимоМеня;
  неКМестуВсего += свод.показовВСвойПодход;
  миганиеВсего += свод.мигало;
  if (название.indexOf('ПАРАМИ') === -1) лишняяНадпись += свод.снадписью;
}

