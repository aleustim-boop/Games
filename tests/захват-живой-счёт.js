/**
 * Раунд с боями: в нём живой счёт интереснее всего (есть что менять). Сервер берёт Math.random — на время
 * поиска подменяем его посевом (тот же, что у ботов): посев № п даёт всегда одну и ту же раздачу, проверка
 * не зависит от удачи. Берём первый посев, где в разборе есть удар.
 */
function дваВидаСБоем() {
  const настоящий = Math.random;
  try {
    for (let п = 1; п <= 200; п++) {
      Math.random = случайСПосевом(п);
      const в = дваВида();
      const з = в.второй.захват;
      if (Array.isArray(з.войскаДо) && з.события.some(с => с.вид === 'удар')) return в;
    }
    return null;
  } finally {
    Math.random = настоящий;
  }
}

