/**
 * Всё, что экран говорит столу про счёт, — в один список по порядку:
 *   { тип: 'счёт', счёт } — задатьСчётРаскрытия; { тип: 'снят' } — снятьСчётРаскрытия;
 *   { тип: 'партия', войска, хозяева } — обновитьПартию (что стол рисует).
 * Настоящий метод стола, если он есть, зовётся следом; нет — следилка сама его даёт.
 */
function поставитьШпиона(стол) {
  const события = [];
  const задатьНастоящий = стол.задатьСчётРаскрытия;
  const снятьНастоящий = стол.снятьСчётРаскрытия;
  const обновитьНастоящий = стол.обновитьПартию;
  if (typeof обновитьНастоящий !== 'function') throw new Error('У стола нет обновитьПартию');
  стол.задатьСчётРаскрытия = function (счёт) {
    события.push({ тип: 'счёт', счёт: JSON.parse(JSON.stringify(счёт)) });
    return typeof задатьНастоящий === 'function' ? задатьНастоящий.apply(this, arguments) : undefined;
  };
  стол.снятьСчётРаскрытия = function () {
    события.push({ тип: 'снят' });
    return typeof снятьНастоящий === 'function' ? снятьНастоящий.apply(this, arguments) : undefined;
  };
  стол.обновитьПартию = function (партия) {
    события.push({ тип: 'партия', войска: партия.войска ? партия.войска.slice() : null, хозяева: партия.хозяева.slice() });
    return обновитьНастоящий.apply(this, arguments);
  };
  return события;
}

