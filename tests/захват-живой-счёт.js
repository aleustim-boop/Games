function ломающиеЗапуски(папка) {
  fs.mkdirSync(папка, { recursive: true });
  let худшее = 0;
  ПОРЧИ.forEach((порча, номер) => {
    const исходник = { экран: исходникЭкрана, модуль: исходникМодуля, стол: исходникСтола, память: fs.readFileSync(ФАЙЛ_ПАМЯТИ, 'utf8') }[порча.файл];
    const частей = исходник.split(порча.было).length - 1;
    if (частей !== 1) {
      console.log('ПОРЧА НЕ СДЕЛАНА: «' + порча.имя + '» — мест для порчи ' + частей + ' (нужно ровно одно)');
      худшее = Math.max(худшее, 3);
      return;
    }
    const копия = path.join(папка, 'копия-' + номер + '-' + порча.файл + '.js');
    fs.writeFileSync(копия, исходник.replace(порча.было, () => порча.стало));
    // Подменяется один файл — тот, что испорчен; остальные берутся как в этом запуске.
    const пути = { экран: ФАЙЛ_ЭКРАНА, модуль: ФАЙЛ_МОДУЛЯ, стол: ФАЙЛ_СТОЛА, память: ФАЙЛ_ПАМЯТИ };
    пути[порча.файл] = копия;
    const доводы = [__filename, '--файл-экрана', пути.экран, '--файл-модуля', пути.модуль, '--файл-стола', пути.стол, '--файл-памяти', пути.память];
    const итог = spawnSync(process.execPath, доводы, { encoding: 'utf8' });
    const красное = итог.status === 1;
    console.log((красное ? 'покраснело: ' : 'НЕ ПОКРАСНЕЛО: ') + порча.имя + ' (код ' + итог.status + ')');
    if (!красное) худшее = Math.max(худшее, 2);
  });
  process.exit(худшее);
}

