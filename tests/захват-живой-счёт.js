/**
 * Прогнать раскрытие по часам и на каждом моменте, где счёт менялся, сверить стол со счётом шага:
 *   - числа на пилюлях стрелок равны счёт.пилюли (в бою они падают, погибшая колонна гаснет);
 *   - числа на шайбах равны счёт.войска.
 * Потом, на шаге итоговой карты: счёт снят РАНЬШЕ, чем отдана итоговая партия; стрелок-пилюль нет, шайбы — числа партии.
 * Возвращает { моментов, сПилюлями, падений } — вызывающий требует ненулевого (ноль найденного — провал).
 * прошло(мс) — часы своего мира; события() — текущий список следилки.
 */
function пройтиРаскрытие(имя, документ, расписание, прошло, события, итог) {
  const шаги = расписание.шаги;
  const шагИтога = шаги.find(ш => ш.вид === 'итоговая-карта');
  проверка(имя + ': в расписании есть шаг итоговой карты (ноль — провал)', !!шагИтога);
  if (!шагИтога) { прошло(расписание.всегоМс); return { моментов: 0, сПилюлями: 0, падений: 0 }; }
  const моменты = [...new Set(шаги.filter(ш => ш.счёт && ш.с < шагИтога.с).map(ш => ш.с))].sort((а, б) => а - б);
  let время = 0, сПилюлями = 0, падений = 0, прежние = {};
  const расхождения = [];
  for (const с of моменты) {
    прошло(с - время);
    время = с;
    const ждали = шаги.filter(ш => ш.счёт && ш.с === с).pop().счёт;
    if (Object.keys(ждали.пилюли).length) сПилюлями++;
    Object.keys(ждали.пилюли).forEach(к => { if (к in прежние && ждали.пилюли[к] < прежние[к]) падений++; });
    прежние = ждали.пилюли;
    const стрелки = числаНаСтрелках(документ);
    if (вСтроку(стрелки) !== вСтроку(ждали.пилюли)) расхождения.push(с + ' мс: стрелки «' + вСтроку(стрелки) + '» вместо «' + вСтроку(ждали.пилюли) + '»');
    const шайбы = числаНаШайбах(документ);
    const войска = {};
    ждали.войска.forEach((в, о) => { if (о in шайбы) войска[о] = в; });
    if (вСтроку(шайбы) !== вСтроку(войска) || !Object.keys(шайбы).length) расхождения.push(с + ' мс: шайбы «' + вСтроку(шайбы) + '» вместо «' + вСтроку(войска) + '»');
  }
  проверка(имя + ': моменты со счётом найдены (ноль — провал)', моменты.length > 0, String(моменты.length));
  проверка(имя + ': на каждом шаге числа стрелок и шайб стола = снимок счёта', расхождения.length === 0, расхождения.slice(0, 2).join(' | '));
  // Итоговая карта: перед ней — все шаги, внутри — только её шаг.
  прошло(Math.max(0, шагИтога.с - 1 - время));
  const метка = события().length;
  прошло(1);
  const срез = события().slice(метка);
  const иСнят = срез.findIndex(с => с.тип === 'снят');
  const иПартия = срез.findIndex(с => с.тип === 'партия');
  проверка(имя + ': на шаге итоговой карты счёт снят и партия отдана (ноль — провал)', иСнят !== -1 && иПартия !== -1, 'снят ' + иСнят + ', партия ' + иПартия);
  проверка(имя + ': на шаге итоговой карты счёт снят РАНЬШЕ итоговой партии', иСнят !== -1 && иПартия !== -1 && иСнят < иПартия, 'снят ' + иСнят + ', партия ' + иПартия);
  проверка(имя + ': на шаге итоговой карты стол получил войска итоговой партии', иПартия !== -1 && одно(срез[иПартия].войска, итог.войска));
  проверка(имя + ': после снятия счёта пилюль на стрелках нет', Object.keys(числаНаСтрелках(документ)).length === 0, вСтроку(числаНаСтрелках(документ)));
  const шайбы = числаНаШайбах(документ);
  const войска = {};
  итог.войска.forEach((в, о) => { if (о in шайбы) войска[о] = в; });
  проверка(имя + ': после снятия счёта на шайбах числа партии', Object.keys(шайбы).length > 0 && вСтроку(шайбы) === вСтроку(войска), вСтроку(шайбы) + ' / ' + вСтроку(войска));
  прошло(Math.max(0, расписание.всегоМс - шагИтога.с));
  return { моментов: моменты.length, сПилюлями, падений };
}

/**
 * Общие требования к одному раскрытию. итог — { войска, хозяева } партии после разбора.
 * Счёт, снятие и итоговая партия идут именно в этом порядке.
 */
function проверитьКонецРаскрытия(имя, события, итог) {
  const посл = последнийИндекс(события, 'счёт');
  const снят = последнийИндекс(события, 'снят');
  const партия = последнийИндекс(события, 'партия');
  проверка(имя + ': стол получил счёт хотя бы раз (ноль — провал)', счётов(события) > 0, 'счётов ' + счётов(события));
  if (посл === -1) return;
  const с = события[посл].счёт;
  проверка(имя + ': последний счёт — войска итоговой партии', одно(с.войска, итог.войска), JSON.stringify(с.войска) + ' против ' + JSON.stringify(итог.войска));
  проверка(имя + ': последний счёт — хозяева итоговой партии', одно(с.хозяева, итог.хозяева), JSON.stringify(с.хозяева) + ' против ' + JSON.stringify(итог.хозяева));
  проверка(имя + ': после последнего счёта он снят (ноль — провал)', снят > посл, 'последний счёт ' + посл + ', снятие ' + снят);
  проверка(имя + ': итоговая партия отдана столу, когда счёт уже снят', партия !== -1 && счётВключён(события, партия) === false, 'партия ' + партия);
  const п = события[партия];
  проверка(имя + ': стол в конце получил войска итоговой партии', !!п && одно(п.войска, итог.войска) && одно(п.хозяева, итог.хозяева));
}

