#!/usr/bin/env node
'use strict';

/* =====================================================================
   СНИМОК МЕСТ РЕЙТИНГА: стрелка «место выросло/упало» должна опираться
   на настоящие вчерашние места, а не на выдумку.

   Зачем эта проверка существует. Задача штаба от 22.09: хранить суточный
   снимок мест, чтобы экран мог показать стрелку. Сервер раньше хранил
   только сегодняшние очки — сравнивать место было не с чем. Ломается
   это тихо: перепутал день, забыл про сон сервера — и стрелка покажет
   рост там, где на самом деле данных нет вовсе, а игрок примет это за
   правду.

   ЧТО ПРОВЕРЯЕМ:
     1) обычная смена суток: у кого место выросло/упало/не изменилось —
        стрелка про это, у нового игрока (не было в снимке) — «нетДанных»;
     2) сервер спал трое суток — старый снимок НЕ считается вчерашним,
        движение «нетДанных» у всех, даже у тех, кто был в том снимке;
     3) снимка не было вовсе (первый запуск) — тоже «нетДанных», и файл
        снимка после этого появляется на диске;
     4) «все игры» — движение считается по сумме очков всех игр (это
        тоже глобальный ранг, как и место в одной игре);
     5) у половин по правилу и по составу поля «движение» нет вовсе —
        там место не глобальное, врать стрелкой нельзя;
     6) у среза «только друзья» поля «движение» тоже нет — там место
        локальное (1..N среди друзей), а не позиция в общей таблице;
     7) снимок не переписывается на каждый чих: партия в течение ТОГО ЖЕ
        дня не трогает файл вчерашнего снимка;
     8) поле «сдвиг» (на сколько мест точно поднялся/опустился игрок) —
        ровно то число, которого ждём (3→1 места — сдвиг 2, а не
        «просто больше нуля»), и направление (рост/падение) не путается;
     9) поля «сдвиг» НЕТ вовсе при «безИзменений» и при «нетДанных» —
        врать несуществующим числом мест нельзя;
    10) сервер ПЕРЕЗАПУСТИЛИ СРЕДИ ДНЯ: в файле на диске уже лежит
        сегодняшний снимок (кто-то открывал рейтинг раньше сегодня) и
        непустое «вчера» — движение должно взяться из «вчера», честно
        прочитанного с диска функцией загрузитьМеста, а НЕ обнулиться
        только из-за того, что код обновитьСнимокЕслиНужно сразу вышел
        (день не сменился, пересчёта не было вовсе);
    11) битый или пустой файл снимка (мусор вместо JSON, пустая строка)
        не должен ронять сервер — движение «нетДанных» у всех, и на диске
        после обращения появляется новый, исправный файл на сегодня.

   УМЕЕТ ЛИ ОНА КРАСНЕТЬ.
     --сломать берёт временную копию server/рейтинг.js и снимает в ней
     проверку «разница ровно один день» — старый снимок начинает
     считаться вчерашним независимо от того, сколько сервер на самом
     деле спал. На такой копии пункт (2) обязан провалиться: вместо
     честного «нетДанных» появится выдуманное движение по трёхдневной
     давности местам.
     --сломать-сдвиг берёт другую временную копию и подменяет точное
     вычисление «сколько мест прошли» (вчерашнее минус сегодняшнее место)
     на константу 1 — направление (рост/падение) остаётся верным, а само
     число мест врёт. На такой копии пункт (8) обязан провалиться: сдвиг
     3→1 (ждём 2) и 2→5 (ждём 3) внезапно совпадут и оба покажут 1.
     --сломать-вчера берёт третью временную копию и подменяет чтение
     поля «вчера» из файла снимка на всегда-null — при перезапуске среди
     дня (пункт 10) обновитьСнимокЕслиНужно выходит сразу и не пересчитывает
     ничего, а «вчера» в этом случае берётся ТОЛЬКО из того, что прочитано
     с диска. На такой копии пункт (10) обязан провалиться: вместо
     честного «выросло»/«упало» появится «нетДанных» — игрок останется
     без стрелки до конца суток, хотя данные для неё были на диске.
     --сломать-разбор берёт четвёртую временную копию и убирает try/catch
     вокруг разбора файла снимка — битый или пустой файл вместо тихого
     «начинаем с нуля» роняет процесс необработанным исключением. На
     такой копии пункт (11) обязан провалиться.

   Боевых данных не касается: копия server/ и все папки данных — во
   временных каталогах (mkdtempSync), каждый сценарий — отдельный
   дочерний процесс node с собственной GAMES_DATA. Все свои временные
   папки проверка убирает за собой в самом конце прогона.

   Запуск:
     node tests/снимок-мест-рейтинга.js                  (обычный прогон)
     node tests/снимок-мест-рейтинга.js --сломать         (обязан провалиться)
     node tests/снимок-мест-рейтинга.js --сломать-сдвиг   (обязан провалиться)
     node tests/снимок-мест-рейтинга.js --сломать-вчера   (обязан провалиться)
     node tests/снимок-мест-рейтинга.js --сломать-разбор  (обязан провалиться)
   Выход 0 — провалов нет, 1 — провал (смотреть строки «ПРОВАЛ» в выводе).

   ИЗВЕСТНОЕ, НО НЕ ЧИНЕНОЕ ЗДЕСЬ. подготовитьКопиюСервера() копирует всю
   папку server/ целиком, вместе с server/данные — настоящие имена и
   номера игроков (если проверку запустить на машине с боевыми данными
   рядом) уезжают во временную папку вместе с копией кода. Так же
   устроены ещё несколько проверок в этой папке (видно по одинаковому
   приёму cpSync(... 'server' ...)). Это отдельная задача штаба, не
   этой правки — здесь только зафиксировано, чинить не стали.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

// Корень проекта — от папки tests/, как у всех проверок.
const КОРЕНЬ = path.join(__dirname, '..');
const СЛОМАТЬ = process.argv.includes('--сломать');
const СЛОМАТЬ_СДВИГ = process.argv.includes('--сломать-сдвиг');
const СЛОМАТЬ_ВЧЕРА = process.argv.includes('--сломать-вчера');
const СЛОМАТЬ_РАЗБОР = process.argv.includes('--сломать-разбор');

const ПРОВЕРКИ = [];
function проверить(имя, условие, подробности) {
  ПРОВЕРКИ.push({ имя: имя, ошибка: условие ? null : (подробности || 'условие не выполнено') });
}

/* Все временные папки, которые проверка завела за прогон (копия сервера,
   копии данных каждого сценария, папки раннеров) — чтобы убрать их за
   собой в самом конце, а не оставлять по десятку мусорных каталогов
   после каждого запуска. */
const ВСЕ_ВРЕМЕННЫЕ_ПАПКИ = [];

/** Своя временная папка с заданным префиксом — и сразу на учёт для уборки. */
function новаяВременнаяПапка(префикс) {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), префикс));
  ВСЕ_ВРЕМЕННЫЕ_ПАПКИ.push(папка);
  return папка;
}

/** Убрать за собой ВСЕ временные папки этого прогона. Только внутри os.tmpdir(). */
function прибратьВременныеПапки() {
  const корзинаОС = path.resolve(os.tmpdir());
  for (const папка of ВСЕ_ВРЕМЕННЫЕ_ПАПКИ) {
    try {
      const полныйПуть = path.resolve(папка);
      // Подстраховка: не трогаем ничего за пределами временного каталога ОС.
      if (полныйПуть.indexOf(корзинаОС) !== 0) continue;
      fs.rmSync(полныйПуть, { recursive: true, force: true });
    } catch (сбой) {
      // Не убралось — не беда, это не портит результат проверки.
    }
  }
}

/* Страховка: если один из испортитьКопию*() ниже кинет исключение (код
   для порчи изменился, строка не нашлась) — выполнение прервётся ДО
   прибратьВременныеПапки() в конце файла, и уже созданная копия сервера
   останется висеть во временной папке. process.on('exit') срабатывает
   при любом завершении процесса (в том числе на непойманной ошибке),
   поэтому уборка гарантирована независимо от того, где именно прогон
   оборвался. Двойной вызов внизу файла безопасен — rmSync(force) на уже
   убранной папке ничего не делает. */
process.on('exit', прибратьВременныеПапки);

/** Своя копия server/ во временной папке — боевой код и боевые данные не трогаем. */
function подготовитьКопиюСервера() {
  const врем = новаяВременнаяПапка('снимок-мест-рейтинга-');
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(врем, 'server'), { recursive: true });
  /* server/игры/умолчания.js берёт список игр из общего js/игры-реестр.js —
     без него копия сервера не загрузится. */
  fs.mkdirSync(path.join(врем, 'js'), { recursive: true });
  fs.copyFileSync(path.join(КОРЕНЬ, 'js', 'игры-реестр.js'), path.join(врем, 'js', 'игры-реестр.js'));
  return path.join(врем, 'server', 'рейтинг.js');
}

/**
 * Найти в исходнике кусок «было» и заменить на «стало» — независимо от
 * того, какие переводы строк сейчас лежат в файле (\n или \r\n). Строки
 * «было»/«стало» в вызывающем коде всегда пишутся с обычным \n; перед
 * поиском исходник тоже приводится к \n, а результат записывается назад
 * в том стиле переводов строк, в каком файл был прочитан.
 */
function заменитьВИсходнике(путь, было, стало, поясн) {
  const сыройИсходник = fs.readFileSync(путь, 'utf8');
  const этоCRLF = сыройИсходник.indexOf('\r\n') !== -1;
  const исходник = сыройИсходник.replace(/\r\n/g, '\n');
  if (исходник.indexOf(было) === -1) {
    throw new Error('не нашёл строку для порчи (' + поясн +
      ') — код server/рейтинг.js изменился, поправьте tests/снимок-мест-рейтинга.js');
  }
  let испорчено = исходник.replace(было, стало);
  if (этоCRLF) испорчено = испорчено.replace(/\n/g, '\r\n');
  fs.writeFileSync(путь, испорчено, 'utf8');
}

/**
 * Порча копии: снимает проверку «разница ровно один день» между старым
 * и новым снимком — ровно то место, от которого зависит честность
 * «сервер спал трое суток» → «нетДанных».
 */
function испортитьКопию(путьКРейтингу) {
  заменитьВИсходнике(путьКРейтингу,
    'const новоеВчера = (снимокМест.сегодня && снимокМест.сегодня.день === вчерашнийКлюч)\n' +
    '    ? снимокМест.сегодня\n' +
    '    : null;',
    'const новоеВчера = (снимокМест.сегодня /* ИСПОРЧЕНО ПРОВЕРКОЙ tests/снимок-мест-рейтинга.js' +
    ' --сломать: проверка разрыва суток снята */)\n' +
    '    ? снимокМест.сегодня\n' +
    '    : null;',
    'разница ровно один день');
}

/**
 * Порча копии для --сломать-сдвиг: подменяет точное вычисление «сколько
 * мест прошли» (вчерашнее место минус сегодняшнее, по модулю) на
 * константу 1. Направление (выросло/упало) остаётся верным — врёт
 * только число мест, поэтому ловит именно то, что --сломать не ловит.
 */
function испортитьКопиюСдвига(путьКРейтингу) {
  заменитьВИсходнике(путьКРейтингу,
    "    return { движение: 'выросло', сдвиг: вчерашнееМесто - текущееМесто };\n" +
    '  }\n' +
    '  if (текущееМесто > вчерашнееМесто) {\n' +
    "    return { движение: 'упало', сдвиг: текущееМесто - вчерашнееМесто };\n" +
    '  }',
    "    return { движение: 'выросло', сдвиг: 1 /* ИСПОРЧЕНО ПРОВЕРКОЙ" +
    " tests/снимок-мест-рейтинга.js --сломать-сдвиг: точное число мест заменено на константу */ };\n" +
    '  }\n' +
    '  if (текущееМесто > вчерашнееМесто) {\n' +
    "    return { движение: 'упало', сдвиг: 1 };\n" +
    '  }',
    'вычисление сдвига');
}

/**
 * Порча копии для --сломать-вчера: чтение поля «вчера» из файла снимка
 * (в загрузитьМеста) заменяется на всегда-null. При перезапуске среди
 * дня (обновитьСнимокЕслиНужно видит, что «сегодня» в файле уже
 * сегодняшнее, и выходит сразу, ничего не пересчитывая) «вчера» берётся
 * ТОЛЬКО из того, что прочитано с диска — значит эта порча обязана
 * снести стрелку именно в сценарии «перезапуск среди дня» и нигде
 * больше (в остальных сценариях «вчера» приходит из пересчёта, который
 * эта строка не трогает).
 */
function испортитьКопиюВчера(путьКРейтингу) {
  заменитьВИсходнике(путьКРейтингу,
    'вчера: частьСнимкаМест(прочитанное && прочитанное.вчера),',
    'вчера: null, /* ИСПОРЧЕНО ПРОВЕРКОЙ tests/снимок-мест-рейтинга.js --сломать-вчера:' +
    ' чтение «вчера» из файла снято */',
    'чтение «вчера» из файла');
}

/**
 * Порча копии для --сломать-разбор: убирает try/catch вокруг разбора
 * файла снимка — битый или пустой файл вместо тихого «начинаем с нуля»
 * роняет процесс необработанным исключением JSON.parse.
 */
function испортитьКопиюРазбор(путьКРейтингу) {
  заменитьВИсходнике(путьКРейтингу,
    'function загрузитьМеста() {\n' +
    '  ужеЗагрузилиМеста = true;\n' +
    '  try {\n' +
    "    const прочитанное = JSON.parse(fs.readFileSync(файлМест(), 'utf8'));\n" +
    '    снимокМест = {\n' +
    '      вчера: частьСнимкаМест(прочитанное && прочитанное.вчера),\n' +
    '      сегодня: частьСнимкаМест(прочитанное && прочитанное.сегодня)\n' +
    '    };\n' +
    '  } catch (сбой) {\n' +
    '    снимокМест = { вчера: null, сегодня: null };\n' +
    '  }\n' +
    '}',
    'function загрузитьМеста() {\n' +
    '  ужеЗагрузилиМеста = true;\n' +
    '  /* ИСПОРЧЕНО ПРОВЕРКОЙ tests/снимок-мест-рейтинга.js --сломать-разбор:' +
    ' try/catch снят, битый файл роняет процесс */\n' +
    "  const прочитанное = JSON.parse(fs.readFileSync(файлМест(), 'utf8'));\n" +
    '  снимокМест = {\n' +
    '    вчера: частьСнимкаМест(прочитанное && прочитанное.вчера),\n' +
    '    сегодня: частьСнимкаМест(прочитанное && прочитанное.сегодня)\n' +
    '  };\n' +
    '}',
    'try/catch вокруг разбора файла снимка');
}

/** «2026-09-21» со сдвигом в днях от сегодня (для дат в подставных снимках). */
function деньСоСдвигом(сдвигДней) {
  const дата = new Date(Date.now() + сдвигДней * 24 * 60 * 60 * 1000);
  const два = (ч) => String(ч).padStart(2, '0');
  return дата.getFullYear() + '-' + два(дата.getMonth() + 1) + '-' + два(дата.getDate());
}

/** Записать рейтинг.json в папку данных — минимальный набор полей, как читает загрузить(). */
function записатьРейтинг(папкаДанных, игроки) {
  fs.mkdirSync(папкаДанных, { recursive: true });
  fs.writeFileSync(path.join(папкаДанных, 'рейтинг.json'), JSON.stringify({ игроки: игроки }), 'utf8');
}

/** Записать рейтинг-места.json — снимок вчера/сегодня, либо не писать вовсе (null). */
function записатьСнимокМест(папкаДанных, снимок) {
  if (снимок === null) return; // сценарий «файла нет вовсе»
  fs.mkdirSync(папкаДанных, { recursive: true });
  fs.writeFileSync(path.join(папкаДанных, 'рейтинг-места.json'), JSON.stringify(снимок), 'utf8');
}

/** Записать рейтинг-места.json СЫРЫМ текстом (для битого/пустого файла — не JSON.stringify). */
function записатьСыройФайлМест(папкаДанных, сыройТекст) {
  fs.mkdirSync(папкаДанных, { recursive: true });
  fs.writeFileSync(path.join(папкаДанных, 'рейтинг-места.json'), сыройТекст, 'utf8');
}

/** Запись игрока рейтинга в минимальном виде. */
function игрок(игра, номер, очки, партий) {
  return { игра: игра, номер: номер, имя: 'И' + номер, очки: очки, побед: 0, ничьих: 0,
    партий: партий || 1, последняяИгра: деньСоСдвигом(0) };
}

/**
 * Запустить раннер (JS-код строкой) в отдельном процессе и вернуть
 * последнюю строку stdout как JSON. При сбое дочернего процесса (не
 * нулевой код выхода, например из-за --сломать-разбор) печатает его
 * stderr — иначе причина падения видна только по коду выхода, а сам
 * текст ошибки молча теряется — и пробрасывает исключение дальше:
 * вызывающая сторона решает, ждала она такого сбоя или нет.
 */
function запуститьРаннер(путьКРейтингу, папкаДанных, действия) {
  const врем = новаяВременнаяПапка('снимок-мест-рейтинга-раннер-');
  const файлРаннера = path.join(врем, 'раннер.js');
  const код = [
    "process.env.GAMES_DATA = " + JSON.stringify(папкаДанных) + ";",
    "const рейтинг = require(" + JSON.stringify(путьКРейтингу) + ");",
    "const fs = require('fs');",
    "рейтинг.включитьЗапись();",
    действия
  ].join('\n');
  fs.writeFileSync(файлРаннера, код, 'utf8');
  try {
    const вывод = execFileSync(process.execPath, [файлРаннера],
      { stdio: 'pipe', encoding: 'utf8', timeout: 20000 });
    const строки = вывод.trim().split('\n');
    return JSON.parse(строки[строки.length - 1]);
  } catch (сбой) {
    if (сбой && сбой.stderr) {
      console.error('--- stderr дочернего процесса (' + файлРаннера + ') ---');
      console.error(String(сбой.stderr));
    }
    throw сбой;
  }
}

