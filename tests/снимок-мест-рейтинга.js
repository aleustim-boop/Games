#!/usr/bin/env node
'use strict';

/* =====================================================================
   СНИМОК МЕСТ РЕЙТИНГА: стрелка «место выросло/упало» должна опираться
   на настоящие вчерашние места, а не на выдумку.

   Зачем эта проверка существует. Задача штаба от 22.09: хранить суточный
   снимок мест, чтобы экран мог показать стрелку. Сервер раньше хранил
   только сегодняшние очки — сравнивать место было не с чем. Ломается
   это тихо: перепутал день, забыл про сон сервера — и стрелка покажет
   рост там, где на самом деле данных нет вовсе, а игрок примет это за
   правду.

   ЧТО ПРОВЕРЯЕМ:
     1) обычная смена суток: у кого место выросло/упало/не изменилось —
        стрелка про это, у нового игрока (не было в снимке) — «нетДанных»;
     2) сервер спал трое суток — старый снимок НЕ считается вчерашним,
        движение «нетДанных» у всех, даже у тех, кто был в том снимке;
     3) снимка не было вовсе (первый запуск) — тоже «нетДанных», и файл
        снимка после этого появляется на диске;
     4) «все игры» — движение считается по сумме очков всех игр (это
        тоже глобальный ранг, как и место в одной игре);
     5) у половин по правилу и по составу поля «движение» нет вовсе —
        там место не глобальное, врать стрелкой нельзя;
     6) у среза «только друзья» поля «движение» тоже нет — там место
        локальное (1..N среди друзей), а не позиция в общей таблице;
     7) снимок не переписывается на каждый чих: партия в течение ТОГО ЖЕ
        дня не трогает файл вчерашнего снимка.

   УМЕЕТ ЛИ ОНА КРАСНЕТЬ. node снимок-мест-рейтинга.js --сломать берёт
   временную копию server/рейтинг.js и снимает в ней проверку «разница
   ровно один день» — старый снимок начинает считаться вчерашним
   независимо от того, сколько сервер на самом деле спал. На такой копии
   пункт (2) обязан провалиться: вместо честного «нетДанных» появится
   выдуманное движение по трёхдневной давности местам.

   Боевых данных не касается: копия server/ и все папки данных — во
   временных каталогах (mkdtempSync), каждый сценарий — отдельный
   дочерний процесс node с собственной GAMES_DATA.

   Запуск:
     node tests/снимок-мест-рейтинга.js             (обычный прогон)
     node tests/снимок-мест-рейтинга.js --сломать   (обязан провалиться)
   Выход 0 — провалов нет, 1 — провал (смотреть строки «ПРОВАЛ» в выводе).
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

// Корень проекта — от папки tests/, как у всех проверок.
const КОРЕНЬ = path.join(__dirname, '..');
const СЛОМАТЬ = process.argv.includes('--сломать');

const ПРОВЕРКИ = [];
function проверить(имя, условие, подробности) {
  ПРОВЕРКИ.push({ имя: имя, ошибка: условие ? null : (подробности || 'условие не выполнено') });
}

/** Своя копия server/ во временной папке — боевой код и боевые данные не трогаем. */
function подготовитьКопиюСервера() {
  const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'снимок-мест-рейтинга-'));
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(врем, 'server'), { recursive: true });
  return path.join(врем, 'server', 'рейтинг.js');
}

/**
 * Порча копии: снимает проверку «разница ровно один день» между старым
 * и новым снимком — ровно то место, от которого зависит честность
 * «сервер спал трое суток» → «нетДанных».
 */
function испортитьКопию(путьКРейтингу) {
  const исходник = fs.readFileSync(путьКРейтингу, 'utf8');
  const было = 'const новоеВчера = (снимокМест.сегодня && снимокМест.сегодня.день === вчерашнийКлюч)\r\n' +
    '    ? снимокМест.сегодня\r\n' +
    '    : null;';
  if (исходник.indexOf(было) === -1) {
    throw new Error('не нашёл строку для порчи — код server/рейтинг.js изменился, поправьте tests/снимок-мест-рейтинга.js');
  }
  const испорчено = исходник.replace(было,
    'const новоеВчера = (снимокМест.сегодня /* ИСПОРЧЕНО ПРОВЕРКОЙ tests/снимок-мест-рейтинга.js --сломать: проверка разрыва суток снята */)\r\n' +
    '    ? снимокМест.сегодня\r\n' +
    '    : null;');
  fs.writeFileSync(путьКРейтингу, испорчено, 'utf8');
}

/** «2026-09-21» со сдвигом в днях от сегодня (для дат в подставных снимках). */
function деньСоСдвигом(сдвигДней) {
  const дата = new Date(Date.now() + сдвигДней * 24 * 60 * 60 * 1000);
  const два = (ч) => String(ч).padStart(2, '0');
  return дата.getFullYear() + '-' + два(дата.getMonth() + 1) + '-' + два(дата.getDate());
}

/** Записать рейтинг.json в папку данных — минимальный набор полей, как читает загрузить(). */
function записатьРейтинг(папкаДанных, игроки) {
  fs.mkdirSync(папкаДанных, { recursive: true });
  fs.writeFileSync(path.join(папкаДанных, 'рейтинг.json'), JSON.stringify({ игроки: игроки }), 'utf8');
}

/** Записать рейтинг-места.json — снимок вчера/сегодня, либо не писать вовсе (null). */
function записатьСнимокМест(папкаДанных, снимок) {
  if (снимок === null) return; // сценарий «файла нет вовсе»
  fs.mkdirSync(папкаДанных, { recursive: true });
  fs.writeFileSync(path.join(папкаДанных, 'рейтинг-места.json'), JSON.stringify(снимок), 'utf8');
}

/** Запись игрока рейтинга в минимальном виде. */
function игрок(игра, номер, очки, партий) {
  return { игра: игра, номер: номер, имя: 'И' + номер, очки: очки, побед: 0, ничьих: 0,
    партий: партий || 1, последняяИгра: деньСоСдвигом(0) };
}

/** Запустить раннер (JS-код строкой) в отдельном процессе и вернуть последнюю строку stdout как JSON. */
function запуститьРаннер(путьКРейтингу, папкаДанных, действия) {
  const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'снимок-мест-рейтинга-раннер-'));
  const файлРаннера = path.join(врем, 'раннер.js');
  const код = [
    "process.env.GAMES_DATA = " + JSON.stringify(папкаДанных) + ";",
    "const рейтинг = require(" + JSON.stringify(путьКРейтингу) + ");",
    "const fs = require('fs');",
    "рейтинг.включитьЗапись();",
    действия
  ].join('\n');
  fs.writeFileSync(файлРаннера, код, 'utf8');
  const вывод = execFileSync(process.execPath, [файлРаннера], { stdio: 'pipe', encoding: 'utf8' });
  const строки = вывод.trim().split('\n');
  return JSON.parse(строки[строки.length - 1]);
}

/* -----------------------------------------------------------------------
   Сценарий A: обычная смена суток — рост, падение, без изменений, новый
   игрок; плюс половины и друзья без движения; плюс файл не переписывается
   в течение того же дня.
   ----------------------------------------------------------------------- */
function сценарийA(путьКРейтингу) {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'снимок-мест-A-'));
  записатьРейтинг(папка, [
    игрок('дурак', 601, 100), игрок('дурак', 602, 90),
    игрок('дурак', 603, 80), игрок('дурак', 604, 70)
  ]);
  // Вчера: 601 был вторым, 602 первым, 603 третьим; 604 — новичок, его вчера не было.
  записатьСнимокМест(папка, {
    вчера: null,
    сегодня: { день: деньСоСдвигом(-1), места: { дурак: { '601': 2, '602': 1, '603': 3 } } }
  });

  return запуститьРаннер(путьКРейтингу, папка, [
    "const movements = {};",
    "for (const н of [601,602,603,604]) movements[н] = рейтинг.срезДляИгрока('дурак', н).я.движение;",
    "const половины = рейтинг.срезСоВсемиПравилами('дурак', 601);",
    "const содержитДвижениеПравило = половины.поПравилу.подкидной.я && ('движение' in половины.поПравилу.подкидной.я);",
    "const содержитДвижениеСостав = половины.поСоставу.личный.я && ('движение' in половины.поСоставу.личный.я);",
    "const друзья = рейтинг.срезПоСписку('дурак', 601, [602]);",
    "const содержитДвижениеДрузья = друзья.я && ('движение' in друзья.я);",
    "const путьМест = рейтинг.ФАЙЛ_МЕСТ;",
    "const файлДо = fs.readFileSync(путьМест, 'utf8');",
    "рейтинг.учестьПартию('дурак', [{номер:602,имя:'И602',этоБот:false,победил:true}," +
      "{номер:9001,имя:'X',этоБот:false,победил:false}]);",
    "рейтинг.учестьПартию('дурак', [{номер:602,имя:'И602',этоБот:false,победил:true}," +
      "{номер:9002,имя:'Y',этоБот:false,победил:false}]);",
    "const файлПосле = fs.readFileSync(путьМест, 'utf8');",
    "console.log(JSON.stringify({movements, содержитДвижениеПравило: Boolean(содержитДвижениеПравило)," +
      " содержитДвижениеСостав: Boolean(содержитДвижениеСостав)," +
      " содержитДвижениеДрузья: Boolean(содержитДвижениеДрузья)," +
      " файлНеИзменился: файлДо === файлПосле}));"
  ].join('\n'));
}

/* -----------------------------------------------------------------------
   Сценарий B: сервер спал трое суток — старый снимок не годится в «вчера».
   ----------------------------------------------------------------------- */
function сценарийB(путьКРейтингу) {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'снимок-мест-B-'));
  записатьРейтинг(папка, [игрок('дурак', 801, 100), игрок('дурак', 802, 90)]);
  // Последний снимок сделан три дня назад — это не «вчера», доверять ему нельзя.
  записатьСнимокМест(папка, {
    вчера: null,
    сегодня: { день: деньСоСдвигом(-3), места: { дурак: { '801': 2, '802': 1 } } }
  });

  return запуститьРаннер(путьКРейтингу, папка, [
    "const movements = {};",
    "for (const н of [801,802]) movements[н] = рейтинг.срезДляИгрока('дурак', н).я.движение;",
    "console.log(JSON.stringify({movements}));"
  ].join('\n'));
}

/* -----------------------------------------------------------------------
   Сценарий C: снимка не было вовсе (первый запуск сервера).
   ----------------------------------------------------------------------- */
function сценарийC(путьКРейтингу) {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'снимок-мест-C-'));
  записатьРейтинг(папка, [игрок('дурак', 901, 10)]);
  // рейтинг-места.json нарочно не создаём.

  return запуститьРаннер(путьКРейтингу, папка, [
    "const движение = рейтинг.срезДляИгрока('дурак', 901).я.движение;",
    "const путьМест = рейтинг.ФАЙЛ_МЕСТ;",
    "const появился = fs.existsSync(путьМест);",
    "let деньСегодня = null;",
    "if (появился) деньСегодня = JSON.parse(fs.readFileSync(путьМест,'utf8')).сегодня.день;",
    "console.log(JSON.stringify({движение, появился, деньСегодня}));"
  ].join('\n'));
}

/* -----------------------------------------------------------------------
   Сценарий D: «все игры» — сумма очков нескольких игр тоже даёт глобальный
   ранг, движение должно считаться и там.
   ----------------------------------------------------------------------- */
function сценарийD(путьКРейтингу) {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'снимок-мест-D-'));
  // Сегодня: 701 = 50+10 = 60, 702 = 40+30 = 70 → 702 первый, 701 второй.
  записатьРейтинг(папка, [
    игрок('дурак', 701, 50), игрок('дурак', 702, 40),
    игрок('шашки', 701, 10), игрок('шашки', 702, 30)
  ]);
  // Вчера в сумме всех игр было наоборот: 701 первый, 702 второй.
  записатьСнимокМест(папка, {
    вчера: null,
    сегодня: { день: деньСоСдвигом(-1), места: { _всеИгры: { '701': 1, '702': 2 } } }
  });

  return запуститьРаннер(путьКРейтингу, папка, [
    "const movements = {};",
    "for (const н of [701,702]) movements[н] = рейтинг.срезПоВсемИграм(н).я.движение;",
    "console.log(JSON.stringify({movements}));"
  ].join('\n'));
}

/* -----------------------------------------------------------------------
   main
   ----------------------------------------------------------------------- */

const путьКРейтингу = подготовитьКопиюСервера();
if (СЛОМАТЬ) испортитьКопию(путьКРейтингу);

const резА = сценарийA(путьКРейтингу);
проверить('A: место выросло (601 было 2, стало 1)', резА.movements['601'] === 'выросло',
  'получили: ' + резА.movements['601']);
проверить('A: место упало (602 было 1, стало 2)', резА.movements['602'] === 'упало',
  'получили: ' + резА.movements['602']);
проверить('A: место не изменилось (603 было и осталось 3)', резА.movements['603'] === 'безИзменений',
  'получили: ' + резА.movements['603']);
проверить('A: новый игрок без вчерашнего места — нетДанных (604)', резА.movements['604'] === 'нетДанных',
  'получили: ' + резА.movements['604']);
if (!СЛОМАТЬ) {
  проверить('A: у половины по правилу поля «движение» нет', резА.содержитДвижениеПравило === false);
  проверить('A: у половины по составу поля «движение» нет', резА.содержитДвижениеСостав === false);
  проверить('A: у среза «только друзья» поля «движение» нет', резА.содержитДвижениеДрузья === false);
  проверить('A: партия в тот же день не переписывает файл снимка мест', резА.файлНеИзменился === true);
}

const резB = сценарийB(путьКРейтингу);
проверить(
  'B: сервер спал трое суток — движение «нетДанных», а не выдуманное (801)',
  резB.movements['801'] === 'нетДанных',
  'получили: ' + резB.movements['801'] + (СЛОМАТЬ ? ' (ждали провала на сломанной копии)' : '')
);
проверить(
  'B: сервер спал трое суток — движение «нетДанных», а не выдуманное (802)',
  резB.movements['802'] === 'нетДанных',
  'получили: ' + резB.movements['802']
);

if (!СЛОМАТЬ) {
  const резC = сценарийC(путьКРейтингу);
  проверить('C: снимка не было вовсе — движение «нетДанных»', резC.движение === 'нетДанных',
    'получили: ' + резC.движение);
  проверить('C: после обращения файл снимка мест появился на диске', резC.появился === true);
  проверить('C: в новом снимке день — сегодняшний', резC.деньСегодня === деньСоСдвигом(0),
    'на диске день: ' + резC.деньСегодня);

  const резD = сценарийD(путьКРейтингу);
  проверить('D: «все игры» — движение упало (701 было первым, стало вторым)',
    резD.movements['701'] === 'упало', 'получили: ' + резD.movements['701']);
  проверить('D: «все игры» — движение выросло (702 было вторым, стало первым)',
    резD.movements['702'] === 'выросло', 'получили: ' + резD.movements['702']);
}

console.log('');
let провалов = 0;
for (const п of ПРОВЕРКИ) {
  if (п.ошибка) {
    провалов++;
    console.log('  ПРОВАЛ ' + п.имя + ': ' + п.ошибка);
  } else {
    console.log('  ок     ' + п.имя);
  }
}
console.log('');
console.log('Итого проверок: ' + ПРОВЕРКИ.length + ', провалов: ' + провалов);
process.exit(провалов > 0 ? 1 : 0);
