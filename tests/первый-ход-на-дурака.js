'use strict';

/* =====================================================================
   ПРОВЕРКА ПРАВИЛА «ХОДЯТ НА ДУРАКА».

   Что просил владелец. Раньше первым ходил тот, у кого младший козырь,
   — каждую партию заново. Теперь так решается только ПЕРВАЯ партия за
   столом. В следующей ходят на того, кто остался дураком: он отбивается,
   а нападает его сосед по кругу — тот, кто сидит прямо ПЕРЕД ним.

   Когда правило не работает и снова решает младший козырь:
     • первая партия за столом;
     • прошлая кончилась ничьёй;
     • дурак прошлой партии за этим столом больше не сидит.

   Файл проверяет это тремя способами:
     1) на голых правилах (js/game.js) за столами от 2 до 6 и парами;
     2) цепочками настоящих партий бот-против-бота: доиграли — начали
        новую с этим дураком — дурак обязан отбиваться;
     3) на сервере (server/партия-по-сети.js): у сети правило то же самое,
        иначе браузер и сервер разойдутся в том, кто нападает после реванша.

   Запуск:  node tests/первый-ход-на-дурака.js  [сколько цепочек]
   Код возврата: 0 — всё сошлось, 1 — есть нарушения.
   ===================================================================== */

const путь = require('path');
const игра = require(путь.join(__dirname, '..', 'js', 'game.js'));
const сетеваяПартия = require(путь.join(__dirname, '..', 'server', 'партия-по-сети.js'));
const генератор = require(путь.join(__dirname, 'общий-генератор.js'));

генератор.захватитьСлучайность();

const ПРЕДЕЛ_ХОДОВ = 1200;
let провалов = 0;
let проверок = 0;

function проверить(условие, что) {
  проверок++;
  if (!условие) {
    провалов++;
    console.log('  ПРОВАЛ: ' + что);
  }
}

/** Имена мест за столом — те же, что заводит сама игра. */
function места(сколько) {
  const список = ['человек'];
  for (let i = 1; i < сколько; i++) список.push(i === 1 ? 'бот' : 'бот-' + (i + 1));
  return список;
}

/** Кто сидит прямо перед этим игроком по кругу. */
function соседПеред(список, кто) {
  const i = список.indexOf(кто);
  return список[(i - 1 + список.length) % список.length];
}

/** Слепок стола — чтобы поймать ход, который ничего не изменил. */
function слепок(п) {
  const вРуках = п.игроки.map(function (и) { return (п.руки[и] || []).length; }).join('/');
  return [игра.фаза(п), п.стол.length, п.отбой.length, п.колода.length,
          вРуках, п.атакует, (п.пасы || []).join(',')].join('|');
}

/** Доиграть партию ботами до конца. Возвращает имя дурака или null (ничья). */
function доиграть(п, уровень) {
  let шагов = 0;
  while (!п.завершена && шагов++ < ПРЕДЕЛ_ХОДОВ) {
    const место = игра.ктоХодит(п);
    if (место === null) return { дурак: null, беда: 'ходить некому, а партия не окончена' };
    const было = слепок(п);
    игра.ходБота(п, место, уровень);
    if (слепок(п) === было) return { дурак: null, беда: 'ход «' + место + '» ничего не изменил' };
  }
  if (!п.завершена) return { дурак: null, беда: 'партия не кончилась за ' + ПРЕДЕЛ_ХОДОВ + ' ходов' };
  const проигравшие = п.проигравшие || [];
  return { дурак: проигравшие.length > 0 ? проигравшие[0] : null, беда: null };
}

/* ---------------------------------------------------------------------
   ЧАСТЬ 1. Голые правила: кому достаётся первый ход
   --------------------------------------------------------------------- */

console.log('--- Часть 1. Кому достаётся первый ход ---');

for (const сколько of [2, 3, 4, 5, 6]) {
  const имена = места(сколько);
  for (const дурак of имена) {
    const п = игра.создатьПартию({ игроков: сколько, дуракПрошлойПартии: дурак });
    const ждём = соседПеред(имена, дурак);
    проверить(п.атакует === ждём,
      'стол на ' + сколько + ': дурак «' + дурак + '», нападать должен «' + ждём +
      '», а нападает «' + п.атакует + '»');
    проверить(игра.защищается(п) === дурак,
      'стол на ' + сколько + ': отбиваться должен дурак «' + дурак +
      '», а отбивается «' + игра.защищается(п) + '»');
  }
}

/* Парами: дураков двое, но нападать всё равно обязан игрок из выигравшей пары. */
for (const дурак of места(4)) {
  const п = игра.создатьПартию({ игроков: 4, парами: true, дуракПрошлойПартии: дурак });
  проверить(игра.защищается(п) === дурак,
    'парами: отбиваться должен дурак «' + дурак + '», а отбивается «' + игра.защищается(п) + '»');
  проверить(игра.партнёр(п, п.атакует) !== дурак,
    'парами: нападает напарник дурака — значит ходят по своим, а не на дурака');
}

/* ---------------------------------------------------------------------
   ЧАСТЬ 2. Когда правило НЕ работает — снова младший козырь
   --------------------------------------------------------------------- */

console.log('--- Часть 2. Когда снова решает младший козырь ---');

/** Кто первый по младшему козырю — считаем сами, как это делает игра. */
function поМладшемуКозырю(п) {
  let лучший = null;
  let вес = Infinity;
  for (const место of п.игроки) {
    for (const карта of п.руки[место]) {
      if (карта.масть === п.козырь && карта.вес < вес) { вес = карта.вес; лучший = место; }
    }
  }
  return лучший === null ? п.игроки[0] : лучший;
}

for (const сколько of [2, 3, 4, 6]) {
  for (const случай of [undefined, null, '', 'ничья', 'бот-99', 'кто-то ушёл']) {
    генератор.поставитьЗерно(сколько * 1000 + 7);
    const п = игра.создатьПартию({ игроков: сколько, дуракПрошлойПартии: случай });
    проверить(п.атакует === поМладшемуКозырю(п),
      'стол на ' + сколько + ', дурак «' + случай + '»: должен решать младший козырь (' +
      поМладшемуКозырю(п) + '), а нападает «' + п.атакует + '»');
    проверить(п.дуракПрошлойПартии === null,
      'стол на ' + сколько + ', дурак «' + случай + '»: партия не должна помнить такого дурака');
  }
}

/* ---------------------------------------------------------------------
   ЧАСТЬ 3. Цепочки настоящих партий: выиграл — ходишь ты
   --------------------------------------------------------------------- */

const ЦЕПОЧЕК = Math.max(1, Math.floor(Number(process.argv[2]) || 200));
console.log('--- Часть 3. Цепочки партий подряд (' + ЦЕПОЧЕК + ' цепочек по 5 партий) ---');

let партийВЦепочках = 0;
let ничьих = 0;
let бедВЦепочках = 0;

for (const стол of [{ игроков: 2 }, { игроков: 3 }, { игроков: 4 }, { игроков: 6 },
                    { игроков: 4, парами: true }]) {
  let дурак = null;
  let сНачала = 0;          // партий, начатых по младшему козырю
  let наДурака = 0;         // партий, начатых по правилу «ходят на дурака»
  for (let ц = 1; ц <= ЦЕПОЧЕК; ц++) {
    генератор.поставитьЗерно((ц * 104729 + стол.игроков) | 0);
    дурак = null;
    for (let партия = 1; партия <= 5; партия++) {
      const набор = Object.assign({ сложность: 'обычный' }, стол, { дуракПрошлойПартии: дурак });
      const п = игра.создатьПартию(набор);
      if (дурак) {
        наДурака++;
        проверить(игра.защищается(п) === дурак,
          'цепочка (стол ' + стол.игроков + (стол.парами ? ' парами' : '') +
          '): дурак «' + дурак + '» обязан отбиваться, а отбивается «' + игра.защищается(п) + '»');
        проверить(п.атакует !== дурак,
          'цепочка: дурак «' + дурак + '» сам же и нападает — правило вывернуто наизнанку');
      } else {
        сНачала++;
      }
      const итог = доиграть(п, 'обычный');
      партийВЦепочках++;
      if (итог.беда) {
        бедВЦепочках++;
        if (бедВЦепочках <= 3) console.log('  БЕДА: ' + итог.беда);
        дурак = null;
        continue;
      }
      if (итог.дурак === null) ничьих++;
      дурак = итог.дурак;
    }
  }
  console.log('  стол ' + стол.игроков + (стол.парами ? ' парами' : '') +
    ': по младшему козырю начато ' + сНачала + ', по правилу «на дурака» — ' + наДурака);
  проверить(наДурака > 0, 'стол ' + стол.игроков + ': правило «на дурака» не сработало ни разу');
}
console.log('  партий сыграно: ' + партийВЦепочках + ', ничьих: ' + ничьих +
  ', недоигранных: ' + бедВЦепочках);
проверить(бедВЦепочках === 0, 'в цепочках есть недоигранные партии');

/* ---------------------------------------------------------------------
   ЧАСТЬ 4. Сервер играет по тому же правилу
   --------------------------------------------------------------------- */

console.log('--- Часть 4. Сервер (игра по сети) ---');

for (const сколько of [2, 3, 4, 6]) {
  const имена = места(сколько);
  for (const дурак of имена) {
    const п = сетеваяПартия.начатьПартию(дурак, { игроки: имена });
    const ждём = соседПеред(имена, дурак);
    проверить(п.атакует === ждём,
      'сервер, стол на ' + сколько + ': дурак «' + дурак + '», нападать должен «' + ждём +
      '», а нападает «' + п.атакует + '»');
    проверить(игра.защищается(п) === дурак,
      'сервер, стол на ' + сколько + ': отбиваться должен дурак «' + дурак + '»');
  }
}

/* Ничья и ушедший дурак — и на сервере первый ход у младшего козыря. */
for (const случай of [null, undefined, 'кого-то-нет']) {
  const имена = места(4);
  const п = сетеваяПартия.начатьПартию(случай, { игроки: имена });
  проверить(п.атакует === поМладшемуКозырю(п),
    'сервер: при «' + случай + '» должен решать младший козырь, а нападает «' + п.атакует + '»');
}

/* Браузер и сервер обязаны решать ОДИНАКОВО на одной и той же раздаче. */
for (let зерно = 1; зерно <= 300; зерно++) {
  const имена = места(4);
  const дурак = имена[зерно % 4];
  генератор.поставитьЗерно(зерно);
  const вБраузере = игра.создатьПартию({ игроки: имена, дуракПрошлойПартии: дурак });
  генератор.поставитьЗерно(зерно);
  const наСервере = сетеваяПартия.начатьПартию(дурак, { игроки: имена });
  проверить(вБраузере.атакует === наСервере.атакует,
    'раздача ' + зерно + ': браузер сажает ходить «' + вБраузере.атакует +
    '», а сервер «' + наСервере.атакует + '» — правила разошлись');
}

/* ---------------------------------------------------------------------
   ИТОГ
   --------------------------------------------------------------------- */

console.log('\nпроверок сделано: ' + проверок + ', провалов: ' + провалов);
console.log(провалов === 0
  ? '=== Итог: правило «ходят на дурака» соблюдается везде ==='
  : '=== Итог: ПРАВИЛО НАРУШАЕТСЯ, смотрите провалы выше ===');
process.exit(провалов === 0 ? 0 : 1);
