/** Собрать один «экземпляр» экрана шахмат: свежие document/window,
 *  свой мок window.ЛистЕщё (запоминает переданные двери и умеет
 *  спроситьЗавершить — так же, как настоящий js/лист-ещё.js), настоящие
 *  правила, мок рекордов со счётчиком записей. Возвращает всё, что нужно
 *  сценариям проверки. */
function собратьЭкран() {
  const document = создатьDocument();
  построитьРазметку(document);

  const захваченныеНастройки = { двери: null };
  let подтверждениеОткрыто = false;

  const рекордыЗаписи = [];
  const window = {
    document: document,
    localStorage: (function () {
      const память = new Map();
      return {
        getItem: function (k) { return память.has(k) ? память.get(k) : null; },
        setItem: function (k, v) { память.set(k, String(v)); }
      };
    })(),
    location: { href: '', search: '' },
    ШахматыПравила: require(путьКПравилам),
    ШахматыРекорды: {
      открыты: function () { return false; },
      показать: function () {},
      спрятать: function () {}
    },
    ЛистЕщё: {
      // Мок повторяет контракт настоящего js/лист-ещё.js: подключить()
      // запоминает двери и отдаёт спроситьЗавершить(), которая открывает
      // «подтверждение» (здесь — просто флаг, своей плашки этот мок не
      // рисует) и зовёт пауза(), если партия идёт; иначе — false, обычный
      // путь ухода. Так проверяется именно контракт двери «завершить» из
      // js/шахматы-экран.js, а не разметка плашки (та проверена отдельно,
      // в tests/лист-ещё-завершить.js).
      подключить: function (настройки) {
        захваченныеНастройки.двери = настройки.двери;
        return {
          открыть: function () {},
          закрыть: function () {},
          открыт: function () { return подтверждениеОткрыто; },
          освежитьКнопкуНастроек: function () {},
          спроситьЗавершить: function () {
            const дверь = настройки.двери && настройки.двери.завершить;
            if (!дверь || typeof дверь.видна !== 'function' || !дверь.видна()) return false;
            подтверждениеОткрыто = true;
            if (typeof дверь.пауза === 'function') дверь.пауза();
            return true;
          }
        };
      }
    }
  };
  window.window = window;
  const слушателиОкна = {};
  window.addEventListener = function (тип, fn) { (слушателиОкна[тип] = слушателиОкна[тип] || []).push(fn); };
  window._emit = function (тип) { (слушателиОкна[тип] || []).forEach(function (fn) { fn({}); }); };

  const песочница = {
    window: window,
    document: document,
    console: console,
    setTimeout: setTimeout,
    clearTimeout: clearTimeout,
    setInterval: setInterval,
    clearInterval: clearInterval,
    URLSearchParams: URLSearchParams
  };
  vm.createContext(песочница);
  const исходник = fs.readFileSync(путьКФайлу, 'utf8');
  vm.runInContext(исходник, песочница, { filename: путьКФайлу + ' (в памяти)' });

  return {
    document: document,
    window: window,
    двери: function () { return захваченныеНастройки.двери; },
    рекордыЗаписи: рекордыЗаписи
  };
}

/* ---------- сами проверки ---------- */

function прогнатьПроверки() {
  const строки = [];
  let ошибок = 0;
  function проверка(имя, условие, подробности) {
    if (условие) {
      строки.push('OK   ' + имя);
    } else {
      ошибок++;
      строки.push('ПЛОХО ' + имя + (подробности ? ' — ' + подробности : ''));
    }
  }

  // Сценарий 1: дверь «завершить» передана со всеми нужными полями сразу
  // после загрузки (партия «вдвоём» стартует автоматически).
  (function () {
    const экран = собратьЭкран();
    const дверь = экран.двери() && экран.двери().завершить;
    проверка('дверь «завершить» передана в ЛистЕщё.подключить', Boolean(дверь));
    проверка('дверь «завершить»: видна — функция', Boolean(дверь) && typeof дверь.видна === 'function');
    проверка('дверь «завершить»: действие — функция', Boolean(дверь) && typeof дверь.действие === 'function');
    проверка('дверь «завершить»: текст — строка или функция',
      Boolean(дверь) && (typeof дверь.текст === 'string' || typeof дверь.текст === 'function'));
    проверка('дверь «завершить»: пауза — функция', Boolean(дверь) && typeof дверь.пауза === 'function');
    проверка('дверь «завершить»: продолжить — функция', Boolean(дверь) && typeof дверь.продолжить === 'function');
  })();

  // Сценарий 2: партия «вдвоём» идёт сразу после загрузки — видна() истинна,
  // текст — про результат без записи.
  (function () {
    const экран = собратьЭкран();
    const дверь = экран.двери().завершить;
    проверка('вдвоём, партия только началась: видна() === true', дверь.видна() === true);
    const текст = typeof дверь.текст === 'function' ? дверь.текст() : дверь.текст;
    проверка('вдвоём: текст последствия — «Партия закончится без результата.»',
      текст === 'Партия закончится без результата.', 'получено: ' + JSON.stringify(текст));
  })();

  // Сценарий 3: переключились на партию с ботом (кнопка «кнопка-с-ботом») —
  // видна() всё ещё истинна, текст — про то, что результат не запишется.
  (function () {
    const экран = собратьЭкран();
    экран.document.getElementById('кнопка-с-ботом').click();
    const дверь = экран.двери().завершить;
    проверка('с ботом: видна() === true', дверь.видна() === true);
    const текст = typeof дверь.текст === 'function' ? дверь.текст() : дверь.текст;
    проверка('с ботом: текст последствия — «Партия прервётся, результат не запишется.»',
      текст === 'Партия прервётся, результат не запишется.', 'получено: ' + JSON.stringify(текст));
  })();

  // Сценарий 4: действие() с ботом — рекорд НЕ пишется, партия помечается
  // завершённой (видна() становится ложной), человека уводит на витрину.
  (function () {
    const экран = собратьЭкран();
    экран.document.getElementById('кнопка-с-ботом').click();
    const дверь = экран.двери().завершить;
    let записатьПартиюВызвана = false;
    экран.window.ШахматыРекорды.записатьПартию = function () { записатьПартиюВызвана = true; };
    экран.window.location.href = '';
    дверь.действие();
    проверка('действие() с ботом: window.ШахматыРекорды.записатьПартию НЕ вызван', !записатьПартиюВызвана);
    проверка('действие(): после завершения видна() === false', дверь.видна() === false);
    проверка('действие(): человека увело на витрину (location.href содержит index.html)',
      экран.window.location.href.indexOf('index.html') === 0, 'получено: ' + JSON.stringify(экран.window.location.href));
  })();

  // Сценарий 5 («оживление», позитивный кейс): ПОКА партия идёт — клик по
  // клетке с фигурой (e2, белая пешка) её поднимает, класс «поле--выбрано»
  // появляется. Доказывает, что мок клика/closest в этом файле вообще
  // способен что-то найти — без этого сценарий 6 ниже мог бы «краснеть
  // молча» (ноль найденного и там, и там выглядели бы одинаково).
  (function () {
    const экран = собратьЭкран();
    const узелДоски = экран.document.getElementById('доска');
    // Клетки создаёт сам файл (построитьДоску) — найдём e2 по data-поле.
    const клеткаE2 = узелДоски.children.find(function (к) { return к.getAttribute('data-поле') === 'e2'; });
    проверка('до завершения: клетка e2 найдена на доске', Boolean(клеткаE2));
    if (клеткаE2) {
      узелДоски._emit('click', { target: клеткаE2 });
      проверка('до завершения: клик по e2 поднимает фигуру (класс «поле--выбрано»)',
        клеткаE2.classList.contains('поле--выбрано'));
    }
  })();

  // Сценарий 6 («оживление», требование задания): партия ЗАВЕРШЕНА через
  // действие() двери — повторный клик по e2 фигуру НЕ поднимает: старая
  // «Продолжить партию» не оживляет то, что уже кончилось.
  (function () {
    const экран = собратьЭкран();
    экран.document.getElementById('кнопка-с-ботом').click();
    const дверь = экран.двери().завершить;
    дверь.действие();
    const узелДоски = экран.document.getElementById('доска');
    const клеткаE2 = узелДоски.children.find(function (к) { return к.getAttribute('data-поле') === 'e2'; });
    проверка('после завершения: клетка e2 всё ещё существует', Boolean(клеткаE2));
    if (клеткаE2) {
      узелДоски._emit('click', { target: клеткаE2 });
      проверка('после завершения: клик по e2 НЕ поднимает фигуру (партия не «оживает»)',
        !клеткаE2.classList.contains('поле--выбрано'));
    }
  })();

  // Сценарий 7: «Назад» на столе во время партии не уходит молча — зовёт
  // спроситьЗавершить() мока (тот же путь, что штаб велел для «‹» и
  // стрелки Telegram), а НЕ window.location.href напрямую.
  (function () {
    const экран = собратьЭкран();
    экран.window.location.href = '';
    экран.document.getElementById('кнопка-назад').click();
    проверка('партия идёт, «Назад»: location.href НЕ изменился (подтверждение перехватило уход)',
      экран.window.location.href === '', 'получено: ' + JSON.stringify(экран.window.location.href));
  })();

  // Сценарий 8: партия уже завершена (через действие()) — «Назад» уходит
  // как раньше, без вопроса (спроситьЗавершить видит видна()===false).
  (function () {
    const экран = собратьЭкран();
    экран.document.getElementById('кнопка-с-ботом').click();
    экран.двери().завершить.действие();   // первый уход — уже сработал внутри действие()
    экран.window.location.href = '';       // сбрасываем, чтобы проверить именно следующий клик
    экран.document.getElementById('кнопка-назад').click();
    проверка('партия завершена, «Назад»: уводит на витрину без вопроса',
      экран.window.location.href.indexOf('index.html') === 0, 'получено: ' + JSON.stringify(экран.window.location.href));
  })();

  // Сценарий 9: стрелка Telegram зовёт ТУ ЖЕ функцию ухода, что и «Назад» —
  // подключённый через window.Телеграм.показатьСтрелку колбэк тоже спрашивает
  // подтверждение, пока партия идёт.
  (function () {
    const экран = собратьЭкран();
    let колбэкСтрелки = null;
    экран.window.Телеграм = {
      показатьСтрелку: function (fn) { колбэкСтрелки = fn; },
      спрятатьСтрелку: function () {}
    };
    экран.window._emit('load');   // window.addEventListener('load', освежитьСтрелкуНазад)
    проверка('стрелка Telegram: показатьСтрелку вызван при загрузке', typeof колбэкСтрелки === 'function');
    if (колбэкСтрелки) {
      экран.window.location.href = '';
      колбэкСтрелки();
      проверка('партия идёт, стрелка Telegram: location.href НЕ изменился (тот же путь через подтверждение)',
        экран.window.location.href === '', 'получено: ' + JSON.stringify(экран.window.location.href));
    }
  })();

  return { строки: строки, ошибок: ошибок };
}

