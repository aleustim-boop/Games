const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawn } = require('child_process');
const { chromium, безTelegram, перехватить } = require('./браузер-робот.js');

const ПОРТ = 8961;
const КОРЕНЬ = path.join(__dirname, '..');
const АДРЕС = 'http://127.0.0.1:' + ПОРТ + '/';
const СЛОМАТЬ = process.argv.includes('--сломать');
const ПАПКА_СНИМКОВ = path.join(__dirname, 'снимки');

let всегоПроверок = 0;
let провалов = 0;
function проверить(условие, слова) {
  всегоПроверок++;
  if (условие) console.log('  ок   — ' + слова);
  else { провалов++; console.log('  ПЛОХО— ' + слова); }
}

function поднятьСервер() {
  const сервер = spawn('node', [path.join(__dirname, 'локальный-сервер.js'), String(ПОРТ)], {
    env: Object.assign({}, process.env, { КОРЕНЬ_СЕРВЕРА: КОРЕНЬ }),
    stdio: 'pipe'
  });
  return new Promise((готово, беда) => {
    let вывод = '';
    const таймаут = setTimeout(() => беда(new Error('Сервер не поднялся за 5 секунд')), 5000);
    сервер.stdout.on('data', (д) => {
      вывод += д.toString();
      if (вывод.includes('запущен')) { clearTimeout(таймаут); готово(сервер); }
    });
    сервер.stderr.on('data', (д) => console.log('  ошибка сервера: ' + д.toString().trim()));
    сервер.on('error', (е) => { clearTimeout(таймаут); беда(е); });
  });
}

/* ---------- Порченая копия style-шашки.css для --сломать (во временной папке) ---------- */

function сделатьПорченуюКопию() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'кнопки-как-у-дурака-'));
  const настоящий = fs.readFileSync(path.join(КОРЕНЬ, 'style-шашки.css'), 'utf8');
  // Дописываем в конец файла старое правило — оно снова красит любую обычную
  // кнопку шашек плоским цветом, минуя притемнение общего style.css.
  const порченый = настоящий + '\n' +
    '/* ЛОМАЮЩИЙ ПРОГОН (--сломать, tests/кнопки-как-у-дурака.js): возвращённое\n' +
    '   старое правило — обязано покрасить кнопки шашек снова плоским цветом. */\n' +
    '#приложение .кнопка:not(.кнопка--мелкая):not(.кнопка--выбор) {\n' +
    '  background: var(--сб-акцент);\n' +
    '  color: var(--сб-акцент-текст);\n' +
    '}\n';
  const путь = path.join(папка, 'style-шашки.css');
  fs.writeFileSync(путь, порченый);
  console.log('Порченая копия: ' + путь);
  return путь;
}

async function подсунутьКопию(страница, путьКопии) {
  await перехватить(страница, /\/style-шашки\.css(\?|$)/, (путь) => {
    путь.fulfill({ status: 200, contentType: 'text/css; charset=utf-8', body: fs.readFileSync(путьКопии, 'utf8') });
  });
}

/* ---------- Что смотрим в странице ---------- */

/** Подменяем дверь списка столов: чтобы «Играть онлайн» не звало настоящий
    сервер комнат — его тут нет, а нам нужен только вид кнопки. */
async function подменитьСеть(страница) {
  await страница.evaluate(() => {
    window.Сеть = window.Сеть || {};
    window.Сеть.открытыеСтолы = () => Promise.resolve({ ок: true, узналиВас: true, столы: [] });
  });
}

async function открытьОнлайн(страница, idКарточки) {
  await подменитьСеть(страница);
  const нажато = await страница.evaluate((id) => {
    const к = document.getElementById(id);
    if (!к) return false;
    к.click();
    return true;
  }, idКарточки);
  await страница.waitForTimeout(500);
  return нажато;
}

/** Замер вычисленного вида кнопки: то, что просило задание штаба —
    background-image, background-color, color, border-radius, высота. */
async function замерКнопки(страница, id) {
  return страница.evaluate((id) => {
    const у = document.getElementById(id);
    if (!у) return null;
    const вид = getComputedStyle(у);
    const прямоугольник = у.getBoundingClientRect();
    return {
      фонКартинка: вид.backgroundImage,
      фонЦвет: вид.backgroundColor,
      цвет: вид.color,
      радиус: вид.borderRadius,
      высота: Math.round(прямоугольник.height),
      видна: прямоугольник.width > 0 && прямоугольник.height > 0
    };
  }, id);
}

/** Кнопка вне «Играть онлайн»: показываем её экран напрямую классом
    «экран--виден» (тем же, каким это делает сама игра) — так замер
    честный (настоящая раскладка), а тест не зависит от того, какой
    дорогой в каждой игре до этого экрана добираются кликами — это
    проверяют другие стенды (js/*-лобби.js). */
async function замерКнопкиНаСвоёмЭкране(страница, idЭкрана, idКнопки) {
  await страница.evaluate((idЭкрана) => {
    document.querySelectorAll('.экран--виден').forEach((э) => э.classList.remove('экран--виден'));
    const э = document.getElementById(idЭкрана);
    if (э) э.classList.add('экран--виден');
  }, idЭкрана);
  return замерКнопки(страница, idКнопки);
}

/* ---------- Прогон одной игры ---------- */

async function собратьЗамеры(браузер, копияШашек, игра) {
  const контекст = await браузер.newContext({ viewport: { width: 390, height: 844 } });
  const страница = await контекст.newPage();
  const ошибки = [];
  страница.on('pageerror', (о) => ошибки.push('исключение: ' + о.message));
  страница.on('console', (с) => {
    if (с.type() === 'error' && !/Failed to load resource/.test(с.text())) ошибки.push('консоль: ' + с.text());
  });
  await безTelegram(страница);
  if (игра.файл === 'шашки.html' && копияШашек) await подсунутьКопию(страница, копияШашек);
  await страница.goto(АДРЕС + игра.файл);
  await страница.waitForTimeout(700);

  const замеры = {};

  const открылось = await открытьОнлайн(страница, игра.карточкаОнлайн);
  проверить(открылось, игра.имя + ': карточка «' + игра.карточкаОнлайн + '» (вход в «Играть онлайн») нашлась');
  замеры.создатьИгру = await замерКнопки(страница, 'открытые-столы-создать');
  проверить(замеры.создатьИгру !== null, игра.имя + ': кнопка «Создать игру» (#открытые-столы-создать) нашлась');

  if (игра.снимок) {
    await страница.screenshot({ path: игра.снимок });
    console.log('  снимок: ' + игра.снимок);
  }

  замеры.войтиПоКоду = await замерКнопкиНаСвоёмЭкране(страница, 'экран-друга', 'кнопка-войти-по-коду');
  проверить(замеры.войтиПоКоду !== null, игра.имя + ': кнопка «Войти по коду» (#кнопка-войти-по-коду) нашлась');

  замеры.копироватьКод = await замерКнопкиНаСвоёмЭкране(страница, 'экран-комнаты', 'кнопка-копировать-код');
  проверить(замеры.копироватьКод !== null, игра.имя + ': кнопка «Скопировать код» (#кнопка-копировать-код) нашлась');

  проверить(ошибки.length === 0, игра.имя + ': красных ошибок в консоли нет' + (ошибки.length ? ' — ' + ошибки.join(' | ') : ''));
  await контекст.close();
  return замеры;
}

/** Сравнить замер игры с эталоном дурака по всем полям, которые просило
    задание штаба: background-image, background-color, color, border-radius,
    высота. */
function сравнитьСДураком(имяКнопки, замерИгры, замерДурака, имяИгры) {
  проверить(Boolean(замерИгры) && Boolean(замерДурака),
    имяИгры + ': «' + имяКнопки + '» — оба замера (игры и дурака) есть, есть что сравнивать');
  if (!замерИгры || !замерДурака) return;
  проверить(замерИгры.видна, имяИгры + ': «' + имяКнопки + '» — кнопка видна (не 0×0)');
  проверить(замерИгры.фонКартинка === замерДурака.фонКартинка,
    имяИгры + ': «' + имяКнопки + '» — background-image как у дурака (' + замерИгры.фонКартинка +
    ' против ' + замерДурака.фонКартинка + ')');
  проверить(замерИгры.фонЦвет === замерДурака.фонЦвет,
    имяИгры + ': «' + имяКнопки + '» — background-color как у дурака (' + замерИгры.фонЦвет +
    ' против ' + замерДурака.фонЦвет + ')');
  проверить(замерИгры.цвет === замерДурака.цвет,
    имяИгры + ': «' + имяКнопки + '» — color как у дурака (' + замерИгры.цвет +
    ' против ' + замерДурака.цвет + ')');
  проверить(замерИгры.радиус === замерДурака.радиус,
    имяИгры + ': «' + имяКнопки + '» — border-radius как у дурака (' + замерИгры.радиус +
    ' против ' + замерДурака.радиус + ')');
  проверить(замерИгры.высота === замерДурака.высота,
    имяИгры + ': «' + имяКнопки + '» — высота как у дурака (' + замерИгры.высота +
    ' против ' + замерДурака.высота + ')');
}

async function основной() {
  const копияШашек = СЛОМАТЬ ? сделатьПорченуюКопию() : null;
  if (СЛОМАТЬ) console.log('ЛОМАЮЩИЙ ПРОГОН (только style-шашки.css) — обязан покраснеть.');
  fs.mkdirSync(ПАПКА_СНИМКОВ, { recursive: true });
  const приставка = СЛОМАТЬ ? 'сломано-' : '';
  const сервер = await поднятьСервер();
  let браузер = null;
  try {
    браузер = await chromium.launch();

    const замерыДурака = await собратьЗамеры(браузер, копияШашек,
      { имя: 'Дурак', файл: 'index.html', карточкаОнлайн: 'лобби-играть-онлайн' });
    const замерыШашек = await собратьЗамеры(браузер, копияШашек,
      { имя: 'Шашки', файл: 'шашки.html', карточкаОнлайн: 'лобби-найти-игру',
        снимок: path.join(ПАПКА_СНИМКОВ, приставка + 'кнопки-шашки-390.png') });
    const замерыНард = await собратьЗамеры(браузер, копияШашек,
      { имя: 'Нарды', файл: 'нарды.html', карточкаОнлайн: 'лобби-найти-игру' });

    console.log('\n=== Шашки против дурака ===');
    сравнитьСДураком('Создать игру', замерыШашек.создатьИгру, замерыДурака.создатьИгру, 'Шашки');
    сравнитьСДураком('Войти по коду', замерыШашек.войтиПоКоду, замерыДурака.войтиПоКоду, 'Шашки');
    сравнитьСДураком('Скопировать код', замерыШашек.копироватьКод, замерыДурака.копироватьКод, 'Шашки');

    console.log('\n=== Нарды против дурака ===');
    сравнитьСДураком('Создать игру', замерыНард.создатьИгру, замерыДурака.создатьИгру, 'Нарды');
    сравнитьСДураком('Войти по коду', замерыНард.войтиПоКоду, замерыДурака.войтиПоКоду, 'Нарды');
    сравнитьСДураком('Скопировать код', замерыНард.копироватьКод, замерыДурака.копироватьКод, 'Нарды');
  } finally {
    if (браузер) await браузер.close();
    сервер.kill();
    console.log('\nСервер на ' + ПОРТ + ' погашен (по PID ' + сервер.pid + ').');
  }
  console.log('\nИтого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
  if (провалов > 0) process.exit(1);
}

основной().catch((е) => {
  console.error('ПРОВАЛ ЗАПУСКА: ' + (е && е.stack || е));
  process.exit(1);
});
