'use strict';

/* =====================================================================
   Стенд и автопрогон не должны брать билет на партию с ботом — это не
   партия человека, и очки рейтинга за неё начислять нельзя.

   Признак «идёт стенд» (js/game.js, функция «идётСтенд») читает адрес
   и не зовёт «запроситьБилетНаБота», когда он поднят (см. «начатьПартиюС»).

   КАК ПРОВЕРЯЕМ. Не переписываем условие своими словами — берём НАСТОЯЩИЙ
   текст функции «идётСтенд» и строки её вызова прямо из game.js (баланс
   скобок, без регулярки «жадно до первой скобки») и правда выполняем его
   в песочнице vm с двумя разными адресами: с меткой «стенд» в строке
   поиска и без неё. Так проверка ловит и переименование функции (тогда
   её просто не найдут — см. «ноль найденного»), и потерю условия при
   правке начатьПартиюС.

   ЛОМАЮЩИЙ ЗАПУСК:
       node tests/стенд-без-билета.js --папка=<путь до каталога с game.js>
   Путь ведёт на ИСПОРЧЕННУЮ копию js/ (без признака стенда в условии) —
   настоящий файл проекта эта проверка никогда не трогает и не портит.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const КОРЕНЬ_ПРОЕКТА = path.join(__dirname, '..');

const аргПапка = process.argv.find(function (а) { return а.startsWith('--папка='); });
const ПАПКА_JS = аргПапка ? аргПапка.slice('--папка='.length) : path.join(КОРЕНЬ_ПРОЕКТА, 'js');
const ПУТЬ_К_ИГРЕ = path.join(ПАПКА_JS, 'game.js');

let провалов = 0;
let проверок = 0;
function красный(текст) { провалов++; проверок++; console.log('[ПРОВАЛ] ' + текст); }
function зелёный(текст) { проверок++; console.log('[ок] ' + текст); }

let исходник;
try {
  исходник = fs.readFileSync(ПУТЬ_К_ИГРЕ, 'utf8');
} catch (ошибка) {
  console.log('[ПРОВАЛ] не удалось прочитать ' + ПУТЬ_К_ИГРЕ + ': ' + ошибка.message);
  console.log('Итого проверок: 1, провалов: 1');
  process.exit(1);
}

/**
 * Текст «function имя(...) {...}» из исходника целиком — баланс фигурных
 * скобок посчитан вручную, а не regex-догадкой: тело функции содержит
 * try/catch со своими скобками, нежадный regex оборвал бы его на первой же.
 * Не нашли — null, и вызывающий код обязан покраснеть на этом сам.
 */
function извлечьФункцию(текст, имя) {
  const начало = текст.indexOf('function ' + имя + '(');
  if (начало === -1) return null;
  const открывающая = текст.indexOf('{', начало);
  if (открывающая === -1) return null;
  let глубина = 0;
  for (let i = открывающая; i < текст.length; i++) {
    if (текст[i] === '{') глубина++;
    else if (текст[i] === '}') {
      глубина--;
      if (глубина === 0) return текст.slice(начало, i + 1);
    }
  }
  return null;
}

/**
 * Строка «if (...) вызов(партия);» — ищем ближайший «if (» перед самим
 * вызовом и считаем баланс круглых скобок, чтобы не оборваться на первой
 * же закрывающей (внутри условия свой вызов — «идётСтенд()» — со своими
 * скобками). Между концом условия и началом вызова не должно быть ничего,
 * кроме пробела — иначе это чужой «if», а не тот, что нам нужен.
 */
function извлечьУсловиеВызова(текст, имяВызова) {
  const идВызова = текст.indexOf(имяВызова + '(партия)');
  if (идВызова === -1) return null;
  const кусокДо = текст.slice(0, идВызова);
  const идIf = кусокДо.lastIndexOf('if (');
  if (идIf === -1) return null;
  const открытие = идIf + 3;   // индекс самой «(»
  let глубина = 0;
  let закрытие = -1;
  for (let i = открытие; i < текст.length; i++) {
    if (текст[i] === '(') глубина++;
    else if (текст[i] === ')') {
      глубина--;
      if (глубина === 0) { закрытие = i; break; }
    }
  }
  if (закрытие === -1) return null;
  const междуТекст = текст.slice(закрытие + 1, идВызова).trim();
  if (междуТекст !== '') return null;   // не наш if — между ним и вызовом что-то ещё
  return текст.slice(идIf, идВызова) + имяВызова + '(партия);';
}

const текстИдётСтенд = извлечьФункцию(исходник, 'идётСтенд');
if (!текстИдётСтенд) {
  красный('функция «идётСтенд» не найдена в ' + ПУТЬ_К_ИГРЕ);
} else {
  зелёный('функция «идётСтенд» нашлась в исходнике');
}

const текстУсловия = извлечьУсловиеВызова(исходник, 'запроситьБилетНаБота');
if (!текстУсловия) {
  красный('строка вызова «запроситьБилетНаБота(партия)» с условием не найдена в ' + ПУТЬ_К_ИГРЕ);
} else if (!/идётСтенд\s*\(\s*\)/.test(текстУсловия)) {
  красный('условие перед «запроситьБилетНаБота» не спрашивает «идётСтенд»: ' + текстУсловия);
} else {
  зелёный('условие перед вызовом билета учитывает «идётСтенд»: ' + текстУсловия);
}

// Без обеих находок дальше проверять нечего — выполнять код, которого нет, некому.
if (текстИдётСтенд && текстУсловия) {
  /**
   * Прогнать настоящий код (функцию + условие) в песочнице: свой адрес,
   * свой счётчик вызовов билета — и посмотреть, что получится на самом деле.
   */
  function прогонСценария(естьМеткаСтенда) {
    const песочница = {
      window: { location: { search: естьМеткаСтенда ? '?стенд=' + Date.now() : '' } },
      URLSearchParams: URLSearchParams,
      раздачаДняИдёт: null,     // обычная партия с ботом, не раздача дня
      партия: { пометка: 'партия-для-проверки' },
      вызововБилета: 0
    };
    песочница.запроситьБилетНаБота = function () { песочница.вызововБилета++; };
    vm.createContext(песочница);
    vm.runInContext(текстИдётСтенд + '\n' + текстУсловия, песочница, { filename: 'извлечено-из-game.js' });
    return песочница.вызововБилета;
  }

  const сМеткойСтенда = прогонСценария(true);
  if (сМеткойСтенда === 0) {
    зелёный('с меткой «?стенд=…» в адресе билет НЕ запрашивается');
  } else {
    красный('с меткой «?стенд=…» в адресе билет всё равно запрошен (' + сМеткойСтенда + ' раз)');
  }

  const безМеткиСтенда = прогонСценария(false);
  if (безМеткиСтенда === 1) {
    зелёный('без метки стенда обычная партия с ботом билет запрашивает');
  } else {
    красный('без метки стенда билет запрошен ' + безМеткиСтенда + ' раз(а) вместо одного');
  }
}

console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
process.exit(провалов > 0 ? 1 : 0);
