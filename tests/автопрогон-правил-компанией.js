function прогонРаскладки(раскладка, ходИгрока, кличка, партий, картНаРуки) {
  const итог = { сыграно: 0, шагов: 0, самаяДлинная: 0, сбои: [], зависших: 0, круги: [] };
  const сделатьПартию = картНаРуки
    ? function (настройки) { return создатьКонцовку(настройки, картНаРуки); }
    : null;
  for (let н = 1; н <= партий; н++) {
    /* Зерно зависит от номера партии, раскладки и игрока — значит, любая
       найденная поломка повторяется той же командой слово в слово. */
    const отИгрока = ЗЕРНО_ИГРОКА[кличка] || 0;
    генератор.поставитьЗерно((н * 7919 + раскладка.имя.length * 131 + отИгрока + (картНаРуки || 0) * 611953) | 0);
    const исход = сыгратьПартию(раскладка.настройки, ходИгрока, сделатьПартию);
    итог.сыграно++;
    итог.шагов += исход.шагов || 0;
    if ((исход.шагов || 0) > итог.самаяДлинная) итог.самаяДлинная = исход.шагов || 0;
    if (исход.вечныйКруг) итог.круги.push(кличка + ', партия №' + н + ': ' + исход.вечныйКруг);
    /* Копим замер: сколько подходов подряд игрока законно не звали
       ни нападать, ни отбиваться. Из этого числа и растёт порог
       ПОРОГ_ОБХОДА — он должен стоять выше самого долгого законного
       обхода, иначе проверка начнёт кричать на здоровую игру.
       Партии со сбоями в замер не берём: там расклад уже разъехался. */
    const у = исход.учёт;
    if (у && у.бедДоПроверки === 0 && !исход.вечныйКруг && исход.партия.завершена) {
      if (у.самыйДолгийОбход > замерОбхода.подрядМакс) {
        замерОбхода.подрядМакс = у.самыйДолгийОбход;
        замерОбхода.где = раскладка.имя + (картНаРуки ? ', концовка по ' + картНаРуки : '') +
          ' — ' + кличка + ', партия №' + н + ', обойдён ' + у.ктоОбойдён;
      }
      /* Отдельно — самая длинная партия, в которой кого-то из оставшихся
         за столом не позвали НИ РАЗУ. Это и есть та черта, ниже которой
         проверка обязана молчать. */
      замерОбхода.партийВЗамере++;
      const х = у.хвост || 0;
      замерОбхода.разбросХвостов[х] = (замерОбхода.разбросХвостов[х] || 0) + 1;
      /* Отдельно по раскладкам: за столом на шестерых игрока законно
         обходят дольше, чем на четверых, и порог обязан это выдержать. */
      const ключ = раскладка.имя;
      if (!замерОбхода.поРаскладкам[ключ] || х > замерОбхода.поРаскладкам[ключ]) {
        замерОбхода.поРаскладкам[ключ] = х;
      }
      if (х > замерОбхода.хвостМакс) {
        замерОбхода.хвостМакс = х;
        замерОбхода.хвостГде = раскладка.имя + (картНаРуки ? ', концовка по ' + картНаРуки : '') +
          ' — ' + кличка + ', партия №' + н + ', не звали ' + у.хвостЧей +
          ' (подходов в партии ' + у.подходов + ')';
      }
      if ((у.обойдённые || []).length > 0) {
        замерОбхода.обойдённыхВсего++;
        if (у.подходов > замерОбхода.самаяДлиннаяЧистая) замерОбхода.самаяДлиннаяЧистая = у.подходов;
      }
    }
    if (исход.беды.length) {
      записатьВид(картНаРуки ? 'концовки' : 'полные раздачи', исход.беды[0]);
      if (исход.беды.some(function (т) { return т.indexOf('зависла') === 0; })) итог.зависших++;
      if (итог.сбои.length < ПРИМЕРОВ_НА_РАСКЛАДКУ) {
        итог.сбои.push({ номер: н, беды: исход.беды, журнал: (исход.журнал || []).slice(-14) });
      } else {
        итог.сбои.push({ номер: н, беды: исход.беды, журнал: null });
      }
    }
  }
  return итог;
}

/* =====================================================================
   ТОТ САМЫЙ РАСКЛАД ИЗ ЖАЛОБЫ — РАЗЛОЖЕННЫЙ РУКАМИ

   Случайные партии эту беду ловят редко: ловушка очереди захлопывается
   не с раздачи, а в тот миг, когда выбывает третий, и до него всё идёт
   как у людей. Поэтому расклад собран руками — ровно тот, на который
   жаловался живой игрок, и проверка на нём срабатывает КАЖДЫЙ раз,
   а не когда повезёт.

   Стол на четверых парами, пары через одного: (1,3) и (2,4).
   Третий уже вышел из партии, колода пуста. Первый нападает, отбиваться
   по кругу достаётся второму — напарнику четвёртого. Карты у второго
   заведомо слабые: он берёт подход за подходом.

   Со сломанным правилом ход после каждого «беру» уходил напарнику
   нападавшего, то есть вышедшему третьему, а оттуда возвращался
   напарнику третьего — снова первому. Круг замыкался на двоих,
   и ЧЕТВЁРТЫЙ ЗА ВСЮ ПАРТИЮ НЕ НАПАДАЛ И НЕ ОТБИВАЛСЯ НИ РАЗУ.
   С починенным правилом очередь пары считается исчерпанной, и ход
   идёт дальше по кругу — четвёртому.

   Проверка спрашивает ровно это и ничего больше: побывал ли четвёртый
   хоть раз в главной роли. Кто именно должен получить ход — не
   спрашиваем: это решение игры, и повторять его у себя мы больше
   не будем (см. пояснение в «проверитьЗавершениеПодхода»).
   ===================================================================== */
function собратьРаскладИзЖалобы() {
  const п = игра.создатьПартию({ игроков: 4, парами: true });
  const колода = игра.собратьКолоду(п.размерКолоды);
  const карта = function (имя, масть) {
    for (const к of колода) if (к.имя === имя && к.масть === масть) return к;
    throw new Error('нет карты ' + имя + масть);
  };

  const первый = п.игроки[0];   // нападает
  const второй = п.игроки[1];   // отбивается и берёт; напарник четвёртого
  const третий = п.игроки[2];   // уже вышел — напарник первого
  const четвёртый = п.игроки[3];// его-то и обходят

  /* Козырь — пики. У первого одиннадцать некозырных карт разных
     достоинств: он нападает ими по одной. У второго только мелочь
     чужих мастей — отбиться нечем ни разу, он берёт. У четвёртого
     карты есть, но ходить ему не с чего: слова ему не дают. */
  const рукаПервого = [
    карта('6', '♦'), карта('7', '♦'), карта('8', '♦'), карта('9', '♦'),
    карта('10', '♦'), карта('В', '♦'), карта('Д', '♦'), карта('К', '♦'),
    карта('Т', '♦'), карта('6', '♥'), карта('7', '♥')
  ];
  const рукаВторого = [карта('6', '♣'), карта('7', '♣')];
  const рукаЧетвёртого = [карта('8', '♣'), карта('9', '♣'), карта('10', '♣')];
  const козырная = карта('Т', '♠');

  п.руки = {};
  п.руки[первый] = рукаПервого;
  п.руки[второй] = рукаВторого;
  п.руки[третий] = [];
  п.руки[четвёртый] = рукаЧетвёртого;

  /* Козырную карту в «розданные» не берём нарочно: колода разобрана,
     и она, как всякая сыгранная карта, лежит в отбое. Уберём её отсюда —
     и в партии станет 35 карт вместо 36, а проверка состояния это
     немедленно и заметит (так и вышло с первого раза). */
  const розданы = [].concat(рукаПервого, рукаВторого, рукаЧетвёртого);
  п.колода = [];
  п.отбой = колода.filter(function (к) { return розданы.indexOf(к) === -1; });
  п.козырь = '♠';
  п.козырнаяКарта = козырная;
  п.стол = [];
  п.пасы = [];
  п.берёт = false;
  п.завершена = false;
  п.выбывшие = [третий];
  п.проигравшие = [];
  п.результат = '';
  п.атакует = первый;
  return п;
}

/**
 * Сыграть тот самый расклад и посмотреть, звали ли четвёртого.
 * Играем жадным игроком: он ходит одинаково от прогона к прогону,
 * поэтому и ответ здесь один и тот же, а не «как повезёт».
 */
function проверитьСправедливостьВПарах() {
  const беды = [];
  const исход = сыгратьПартию({ игроков: 4, парами: true }, ходЖадного, собратьРаскладИзЖалобы);
  if (исход.беды.length) {
    // Если по дороге нашлась поломка правил — про очередь говорить рано.
    return исход.беды;
  }
  const учёт = исход.учёт || { участвовал: {}, подходов: 0 };
  const четвёртый = исход.партия.игроки[3];
  const раз = учёт.участвовал[четвёртый] || 0;
  if (учёт.подходов < 5) {
    беды.push('расклад из жалобы не разыгрался: подходов вышло всего ' + учёт.подходов +
      ' — проверять на нём нечего, расклад надо пересобрать');
    return беды;
  }
  if (раз === 0) {
    беды.push('четвёртого игрока «' + четвёртый + '» обошли всю партию: за ' + учёт.подходов +
      ' подходов он ни разу не нападал и не отбивался. Это и есть жалоба живого игрока: ' +
      'ход замкнулся на двоих, остальные смотрят. Кто сколько раз участвовал: ' +
      исход.партия.игроки.map(function (и) {
        return и + ' ' + (учёт.участвовал[и] || 0);
      }).join(', '));
  }
  return беды;
}

