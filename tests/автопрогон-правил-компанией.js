/* =====================================================================
   КОНЦОВКИ: КОЛОДА РАЗОБРАНА, НА РУКАХ ПО ДВЕ-ЧЕТЫРЕ КАРТЫ

   Почему без этого прогон был почти слеп. Зависание живёт там, где
   подкинуть быстро становится нечем НИКОМУ: тогда слово доезжает
   до запасного ответа, и только там видно, кому оно достанется.
   На полной раздаче (колода цела, на руках по шесть карт) такое положение —
   редкость: почти всегда у кого-нибудь найдётся карта нужного достоинства.
   А в концовке оно на каждом шагу.

   Поэтому здесь стол собирается руками: колода уже пуста, на руках
   по две-четыре карты, всё остальное лежит в отбое. Это не выдуманное
   положение — именно так выглядит любая партия за десяток ходов до конца.

   Считать карты это не мешает: их по-прежнему ровно столько, сколько
   в колоде, просто лежат они в другом месте.
   ===================================================================== */

/** Перемешать список своими случайными числами (теми же, что и вся проверка). */
function перетасовать(список) {
  for (let i = список.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const запас = список[i];
    список[i] = список[j];
    список[j] = запас;
  }
  return список;
}

function создатьКонцовку(настройки, картНаРуки) {
  const п = игра.создатьПартию(настройки);
  const все = перетасовать(игра.собратьКолоду(п.размерКолоды));

  const руки = {};
  let взято = 0;
  for (const имя of п.игроки) {
    руки[имя] = все.slice(взято, взято + картНаРуки);
    взято += картНаРуки;
  }
  const остаток = все.slice(взято);
  // Козырь берём у карты, которая давно ушла в отбой: колода разобрана,
  // и открытая козырная карта тоже давно у кого-то побывала.
  const козырная = остаток[остаток.length - 1];

  п.руки = руки;
  п.колода = [];
  п.отбой = остаток;
  п.козырь = козырная.масть;
  п.козырнаяКарта = козырная;
  п.стол = [];
  п.пасы = [];
  п.берёт = false;
  п.завершена = false;
  п.выбывшие = [];
  п.проигравшие = [];
  п.результат = '';
  // Ходит кто угодно: в концовке первый ход давно не за младшим козырем.
  п.атакует = п.игроки[Math.floor(Math.random() * п.игроки.length)];
  return п;
}

/* =====================================================================
   ВЕЧНЫЙ КРУГ

   Отдельный род «партия не кончается», и его важно НЕ ПУТАТЬ с зависанием.
   Зависание — это когда нажать нечего: стол мёртв, и виновата игра.
   А тут у всех есть ходы, все ходят, всё по правилам — просто расклад
   ходит по кругу и не сдвигается: один заходит, другой берёт, карта
   вернулась, отбой не растёт, из-за стола никто не выходит.

   Пример, найденный этой проверкой (трое, козырь ♦, колода пуста):
   6♣ В♠ / 9♥ 8♣ / 9♠ Д♥. Побить тут есть чем — 8♣ бьёт 6♣, В♠ бьёт 9♠,
   Д♥ бьёт 9♥, — но всякий раз нужная карта не у того, кто отбивается.
   Круг замкнулся, и партия повторяется каждые девять ходов вечно.

   Это не поломка кода, а свойство самих правил: правила игры не знают
   слова «ничья». Поэтому такие партии считаются ОТДЕЛЬНО и красной
   проверку не делают — иначе она перестанет отличать сломанную игру
   от целой. Но и молчать о них нельзя: печатаем расклад, чтобы штаб
   мог решить, нужно ли игре правило о ничьей.

   Ловим по повторению расклада: тот же расклад в начале подхода
   встретился четвёртый раз — значит, партия ходит по кругу.
   ===================================================================== */

/** Отпечаток положения: чьи карты, что в колоде и отбое, кто ходит. */
function отпечатокПоложения(партия) {
  const части = [];
  for (const имя of партия.игроки) {
    части.push(имя + ':' + партия.руки[имя].map(имяКарты).slice().sort().join(''));
  }
  части.push('колода:' + партия.колода.map(имяКарты).join(''));
  части.push('отбой:' + партия.отбой.map(имяКарты).slice().sort().join(''));
  части.push('ходит:' + партия.атакует);
  части.push('вышли:' + (партия.выбывшие || []).slice().sort().join(','));
  return части.join('|');
}

