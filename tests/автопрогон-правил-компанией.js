  проверить(игра.пас(п, 'человек') === true, 'человек не смог сказать «Пас», имея на руках карты');
  проверить(п.стол.length === 1, 'подход закончился, хотя боту-3 было чем подкинуть');
  проверить(игра.положитьВАтаку(п, 'бот-3', номер(п, 'бот-3', карта('6', '♥'))) === true,
    'бот-3 не смог подкинуть 6♥ в свою очередь');
  проверить(игра.объявитьБеру(п) === true, 'бот не смог сказать «Беру»');
  проверить(игра.фаза(п) === 'докидывание', 'после «Беру» должна начаться фаза докидывания');

