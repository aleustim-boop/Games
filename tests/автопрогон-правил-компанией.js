function сыгратьПартию(настройки, ходИгрока) {
  const партия = игра.создатьПартию(настройки);
  const журнал = [];
  const беды = [];
  /* Свой список отказов. Заводим его здесь, а не берём у игры: проверка
     должна знать очередь сама, иначе она согласится с любой ошибкой. */
  let спасовавшие = new Set();

  const записать = function (текст) { журнал.push(текст); };

  беды.push.apply(беды, проверитьСостояние(партия));
  if (беды.length) return { беды: беды, журнал: журнал };

  let шагов = 0;
  while (!партия.завершена) {
    if (++шагов > ПРЕДЕЛ_ХОДОВ) {
      беды.push('партия зависла: ' + ПРЕДЕЛ_ХОДОВ + ' ходов, а конца нет (фаза «' + мояФаза(партия) +
        '», слово у «' + моёСлово(партия, спасовавшие) + '», в колоде ' + партия.колода.length + ')');
      break;
    }

    беды.push.apply(беды, проверитьРазметку(партия));
    if (беды.length) break;

    const слово = моёСлово(партия, спасовавшие);
    if (слово === null) { беды.push('слова нет ни у кого, а партия не окончена'); break; }

    // Игра обязана думать о слове то же самое.
    const словоИгры = игра.ктоХодит(партия);
    if (словоИгры !== слово) {
      беды.push('слово должно принадлежать «' + слово + '», а игра отдала его «' + словоИгры +
        '» (фаза «' + мояФаза(партия) + '», спасовали: ' + (Array.from(спасовавшие).join(',') || 'никто') + ')');
      break;
    }

    // Пробные ходы — сверка с двух сторон.
    const бедыПроб = пробы(партия, слово, спасовавшие);
    if (бедыПроб.length) {
      беды.push.apply(беды, бедыПроб);
      break;
    }

    // Настоящий ход.
    const фазаДо = мояФаза(партия);
    const столДо = партия.стол.length;
    const достоинстваДо = моиДостоинства(партия);
    const спасовалРаньше = спасовавшие.has(слово);
    const результат = ходИгрока(партия, слово, спасовавшие);
    записать(слово + ': ' + результат.что + ' (фаза «' + фазаДо + '», на столе было ' + столДо + ')');
    if (результат.отказ) { беды.push(результат.отказ); break; }

    /* Отдельно ловим главную ловушку очереди: слово вернулось к тому,
       кто уже отказался подкидывать, — и он положил карту. Закрыть подход
       ему можно, положить карту нельзя. Проверяем по следу: стол вырос. */
    if (спасовалРаньше && партия.стол.length > столДо) {
      беды.push('игрок ' + слово + ' положил карту, хотя раньше в этом подходе сказал ' +
        '«больше не подкидываю» (слово вернулось к нему только затем, чтобы закрыть подход)');
      break;
    }

    // Ход обязан что-то менять, иначе партия встанет на месте.
    if (!результат.отказ && !партия.завершена && чтоИзменилось(партия, результат.было) === '' &&
        мояФаза(партия) === фазаДо && партия.пасы.length === результат.было.пасы.length) {
      беды.push('ход «' + результат.что + '» игрока ' + слово + ' ничего не изменил — игра стоит на месте');
      break;
    }

    /* Пересчитываем СВОЙ список отказов по тому, что случилось.
       Круг спрашивают заново там, где положение вправду изменилось:
         • защитник отбился картой нового достоинства — всем есть чем подкинуть;
         • защитник сказал «Беру» — подкидывать берущему совсем другое дело;
         • ход перевели — отбивается уже другой, и круг другой;
         • подход закончился — начинается новый.
       От чужой подкинутой карты ничего нового не появляется: подкидывают
       только тем достоинством, что уже лежало. */
    const фазаПосле = мояФаза(партия);
    if (партия.стол.length === 0 || фазаПосле === 'атака' || партия.завершена) {
      спасовавшие = new Set();                                  // подход кончился
    } else if (результат.было.атакует !== партия.атакует) {
      спасовавшие = new Set();                                  // перевод
    } else if (!результат.было.берёт && партия.берёт) {
      спасовавшие = new Set();                                  // сказал «Беру»
    } else if (фазаДо === 'защита' && фазаПосле !== 'защита') {
      const сталоБольше = Array.from(моиДостоинства(партия)).some(function (д) { return !достоинстваДо.has(д); });
      if (сталоБольше) спасовавшие = new Set();                 // отбился новым достоинством
    } else if (результат.что === 'пас' || результат.что === 'ход бота') {
      // Пас мог сказать и бот — узнаём по тому, что карта не легла и стол не изменился.
      const карт = партия.руки[слово] ? партия.руки[слово].length : 0;
      const былоКарт = результат.было.руки[слово] ? результат.было.руки[слово].length : 0;
      if (карт === былоКарт && партия.стол.length === столДо) спасовавшие.add(слово);
    }

    /* Подход закончился — проверяем всё, что случилось разом:
       куда ушли карты, кто сколько добрал, кто вышел, кому достался ход. */
    if (столДо > 0 && партия.стол.length === 0) {
      беды.push.apply(беды, проверитьЗавершениеПодхода(партия, результат.было));
      if (беды.length) break;
    }

    беды.push.apply(беды, проверитьСостояние(партия));
    if (беды.length) break;
  }

  return { беды: беды, журнал: журнал, шагов: шагов, партия: партия };
}

/* =====================================================================
   ЧАСТЬ 1. Разложенный руками стол — тот самый случай живого игрока

   Здесь ничего не случайно: три игрока, известные руки, и проверка
   шаг за шагом повторяет жалобу. Смотрим не на то, что игра ОТВЕЧАЕТ
   на вопрос «можно ли», а на то, что она ДЕЛАЕТ: легла карта или нет.
   ===================================================================== */

function проверитьЖалобуИгрока() {
  const беды = [];
  const колода = игра.собратьКолоду(36);
  const карта = function (имя, масть) {
    for (const к of колода) if (к.имя === имя && к.масть === масть) return к;
    throw new Error('нет карты ' + имя + масть);
  };
  const номер = function (партия, кто, к) { return партия.руки[кто].indexOf(к); };
  const проверить = function (условие, что) { if (!условие) беды.push(что); };

  const п = игра.создатьПартию({ игроков: 3 });
  const руки = {
    'человек': [карта('6', '♣'), карта('6', '♦'), карта('К', '♠'), карта('10', '♥'), карта('В', '♥'), карта('Д', '♥')],
    'бот':     [карта('7', '♣'), карта('9', '♦'), карта('8', '♠'), карта('9', '♠'), карта('10', '♠'), карта('В', '♠')],
    'бот-3':   [карта('6', '♥'), карта('6', '♠'), карта('7', '♦'), карта('8', '♦'), карта('10', '♦'), карта('В', '♦')]
  };
  const розданы = [].concat(руки['человек'], руки['бот'], руки['бот-3']);
  const козырная = карта('Т', '♠');
  п.руки = руки;
  п.колода = колода.filter(function (к) { return розданы.indexOf(к) === -1 && к !== козырная; }).concat([козырная]);
  п.козырь = '♠';
  п.козырнаяКарта = козырная;
  п.стол = [];
  п.отбой = [];
  п.пасы = [];
  п.берёт = false;
  п.завершена = false;
  п.выбывшие = [];
  п.атакует = 'человек';

  проверить(мойЗащитник(п) === 'бот', 'отбиваться должен «бот» — следующий по кругу');

  // Стол пуст: первую карту кладёт только тот, чей ход.
  проверить(игра.положитьВАтаку(п, 'бот-3', номер(п, 'бот-3', карта('6', '♥'))) === false &&
            п.стол.length === 0,
    'бот-3 сумел положить первую карту подхода, хотя ходит человек');

  проверить(игра.положитьВАтаку(п, 'человек', номер(п, 'человек', карта('6', '♣'))) === true,
    'человек не смог зайти 6♣');

  // Пока карта не отбита, не подкидывает никто.
  проверить(игра.положитьВАтаку(п, 'бот-3', номер(п, 'бот-3', карта('6', '♥'))) === false &&
            п.стол.length === 1,
    'бот-3 подкинул 6♥, пока карта на столе не отбита');

  проверить(игра.отбить(п, 0, номер(п, 'бот', карта('7', '♣'))) === true, 'бот не смог отбить 6♣ картой 7♣');

  // ГЛАВНОЕ: слово у человека — он ходил. Второй подкидывающий обязан ждать.
  проверить(мояФаза(п) === 'подкидывание', 'после отбоя фаза должна стать «подкидывание»');
  проверить(игра.положитьВАтаку(п, 'бот-3', номер(п, 'бот-3', карта('6', '♥'))) === false &&
            п.стол.length === 1,
    'бот-3 подкинул 6♥ ВНЕ ОЧЕРЕДИ: слова ему ещё не давали (это и есть жалоба живого игрока)');

  проверить(игра.пас(п, 'человек') === true, 'человек не смог сказать «больше не подкидываю»');
  проверить(п.стол.length === 1, 'подход закончился раньше времени: слово было кому передать');
  проверить(игра.ктоХодит(п) === 'бот-3', 'после паса слово должно перейти боту-3');
  проверить(игра.положитьВАтаку(п, 'бот-3', номер(п, 'бот-3', карта('6', '♥'))) === true,
    'бот-3 не смог подкинуть 6♥, хотя слово уже у него');

  // Новое достоинство на столе — круг начинается заново, от того, кто ходил.
  проверить(игра.отбить(п, 1, номер(п, 'бот', карта('8', '♠'))) === true, 'бот не смог отбить 6♥ козырем 8♠');
  проверить(игра.ктоХодит(п) === 'человек', 'после нового достоинства слово должно вернуться к человеку');
  проверить(игра.положитьВАтаку(п, 'бот-3', номер(п, 'бот-3', карта('6', '♠'))) === false &&
            п.стол.length === 2,
    'бот-3 снова подкинул вне очереди — круг после нового достоинства не начался заново');

  проверить(игра.пас(п, 'человек') === true, 'человек не смог спасовать во второй раз');
  проверить(игра.положитьВАтаку(п, 'бот-3', номер(п, 'бот-3', карта('6', '♠'))) === true,
    'бот-3 не смог подкинуть 6♠ в свою очередь');

  return беды;
}

/* =====================================================================
   ЧАСТЬ 1-Б. Отказ держится до конца подхода

   Второй случай, разложенный по шагам. Он тоньше первого, и его чуть
   не пропустила уже сама эта проверка: когда подкинуть больше некому,
   слово возвращается к тому, кто ходил, — и если он раньше сказал
   «больше не подкидываю», у него появляется соблазн передумать.

   По правилам передумать нельзя: отказ держится до конца подхода,
   а вернувшееся слово даёт право только закрыть подход.

   Стол на троих, козырь ♥:
     Аня заходит 6♣ → Боря кроет 7♣ (достоинство новое, круг заново)
     → Аня пасует, хотя в руке у неё 6♦
     → Вика подкидывает 7♦ → Боря кроет козырной 7♥ (семёрка уже была,
       значит отказы держатся) → Вике больше нечем
     → слово возвращается к Ане. Положить 6♦ она НЕ вправе.
   ===================================================================== */

function проверитьЧтоОтказДержится() {
  const беды = [];
  const колода = игра.собратьКолоду(36);
  const карта = function (имя, масть) {
    for (const к of колода) if (к.имя === имя && к.масть === масть) return к;
    throw new Error('нет карты ' + имя + масть);
  };
  const номер = function (партия, кто, к) { return партия.руки[кто].indexOf(к); };
  const проверить = function (условие, что) { if (!условие) беды.push(что); };

  const п = игра.создатьПартию({ игроков: 3 });
  const руки = {
    'человек': [карта('6', '♣'), карта('6', '♦'), карта('К', '♠'), карта('Д', '♠'), карта('10', '♠'), карта('9', '♠')],
    'бот':     [карта('7', '♣'), карта('7', '♥'), карта('8', '♠'), карта('В', '♠'), карта('10', '♣'), карта('9', '♣')],
    'бот-3':   [карта('7', '♦'), карта('8', '♦'), карта('9', '♦'), карта('10', '♦'), карта('В', '♦'), карта('Д', '♦')]
  };
  const розданы = [].concat(руки['человек'], руки['бот'], руки['бот-3']);
  const козырная = карта('Т', '♥');
  п.руки = руки;
  п.колода = колода.filter(function (к) { return розданы.indexOf(к) === -1 && к !== козырная; }).concat([козырная]);
  п.козырь = '♥';
  п.козырнаяКарта = козырная;
  п.стол = [];
  п.отбой = [];
  п.пасы = [];
  п.берёт = false;
  п.завершена = false;
  п.выбывшие = [];
  п.атакует = 'человек';

  проверить(игра.положитьВАтаку(п, 'человек', номер(п, 'человек', карта('6', '♣'))) === true,
    'человек не смог зайти 6♣');
  проверить(игра.отбить(п, 0, номер(п, 'бот', карта('7', '♣'))) === true, 'бот не смог отбить 6♣ картой 7♣');
  проверить(игра.пас(п, 'человек') === true, 'человек не смог отказаться подкидывать');
  проверить(п.стол.length === 1, 'подход закончился, хотя у бота-3 было чем подкинуть');
  проверить(игра.положитьВАтаку(п, 'бот-3', номер(п, 'бот-3', карта('7', '♦'))) === true,
    'бот-3 не смог подкинуть 7♦ в свою очередь');
  проверить(игра.отбить(п, 1, номер(п, 'бот', карта('7', '♥'))) === true, 'бот не смог отбить 7♦ козырем 7♥');

  // Подкинуть больше некому: у бота-3 не осталось ни шестёрок, ни семёрок.
  проверить(игра.ктоХодит(п) === 'человек', 'слово должно вернуться к человеку — больше спрашивать некого');

  // ГЛАВНОЕ: слово вернулось только затем, чтобы закрыть подход.
  const столДо = п.стол.length;
  const легло = игра.положитьВАтаку(п, 'человек', номер(п, 'человек', карта('6', '♦')));
  проверить(легло === false && п.стол.length === столДо,
    'человек положил 6♦ ПОСЛЕ своего же отказа: слово вернулось к нему только для того, ' +
    'чтобы закрыть подход, а передумывать правила не дают');

  // Закрыть подход он при этом обязан мочь — иначе игра встанет.
  проверить(игра.пас(п, 'человек') === true, 'человек не смог закрыть подход, хотя подкидывать больше некому');
  проверить(п.стол.length === 0, 'подход не закрылся, хотя слова ждать больше не от кого');

  return беды;
}

/* =====================================================================
   РАЗДАЧА, ПОСЧИТАННАЯ ЗАНОВО

   До первого хода уже есть что проверять: сколько карт роздано, где лежит
   козырная и — главное — кто ходит первым. Первым ходит тот, у кого самый
   младший козырь за ВСЕМ столом, а не за парой соседей; нет козырей
   ни у кого — ходит сидящий первым. Компанией это правило легко сломать
   незаметно: вдвоём ошибка видна сразу, а вшестером «не тот начал»
   никто не заметит.
   ===================================================================== */

function проверитьРаздачу(раскладка, раздач) {
  const беды = [];
  for (let н = 1; н <= раздач && беды.length < 3; н++) {
    зерно = н * 104729 + раскладка.имя.length * 17 + 13;
    const п = игра.создатьПартию(раскладка.настройки);
    const мест = п.игроки.length;

    for (const имя of п.игроки) {
      if (п.руки[имя].length !== 6) {
        беды.push('раздача ' + н + ': у ' + имя + ' на руках ' + п.руки[имя].length + ' карт вместо шести');
      }
    }
    const ждёмВКолоде = п.размерКолоды - 6 * мест;
    if (п.колода.length !== ждёмВКолоде) {
      беды.push('раздача ' + н + ': в колоде ' + п.колода.length + ' карт, а по счёту должно быть ' + ждёмВКолоде);
    }
    if (п.колода[п.колода.length - 1] !== п.козырнаяКарта) {
      беды.push('раздача ' + н + ': козырная карта не лежит под колодой');
    }
    if (п.козырнаяКарта.масть !== п.козырь) {
      беды.push('раздача ' + н + ': козырь «' + п.козырь + '» не совпал с козырной картой ' + имяКарты(п.козырнаяКарта));
    }

    // Кто должен был начать: младший козырь за всем столом.
    let началБы = п.игроки[0];
    let младший = null;
    for (const имя of п.игроки) {
      for (const к of п.руки[имя]) {
        if (к.масть !== п.козырь) continue;
        if (младший === null || к.вес < младший.вес) { младший = к; началБы = имя; }
      }
    }
    if (п.атакует !== началБы) {
      беды.push('раздача ' + н + ': первым ходит «' + п.атакует + '», а младший козырь ' +
        (младший ? имяКарты(младший) : 'отсутствует') + ' у «' + началБы + '»');
    }
  }
  return беды;
}

