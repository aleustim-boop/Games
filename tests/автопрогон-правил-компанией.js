const path = require('path');
const fs = require('fs');

const ПАРТИЙ = Number(process.argv[2]) || 40;      // партий на каждую раскладку каждым игроком
/* Третьим доводом можно дать свой файл игры — это нужно, чтобы прогнать
   проверку по нарочно сломанной копии и убедиться, что она вообще умеет
   ловить. Чёрточкой «-» его можно пропустить, когда дальше идут именные
   доводы вроде «порог-обхода»: без этого чёрточка или само слово
   принимались за путь, и прогон падал, не начавшись. */
const ПУТЬ_СВОЙ = (function () {
  const д = process.argv[3];
  if (!д || д === '-' || д.indexOf('порог-обхода') === 0) return '';
  return д;
})();
const ПУТЬ_К_ИГРЕ = ПУТЬ_СВОЙ
  ? path.resolve(ПУТЬ_СВОЙ)
  : path.join(__dirname, '..', 'js', 'game.js');
const игра = require(ПУТЬ_К_ИГРЕ);

/* ---------------------------------------------------------------------
   Сборка вида для игрока — та самая, из которой игрок видит, что ему
   сейчас можно (см. пробу «обещание против дела» ниже).

   Путь к ней не задаём отдельным доводом, а выводим из пути к игре:
   лежит рядом, в соседней папке. Сделано так нарочно. Сервер внутри
   себя пишет require('../js/game.js'), то есть правила берёт СВОИ,
   соседние. Возьми мы всегда нынешний сервер, а игру — старую, вышло бы
   самое коварное: две разные книги правил в одной проверке, и красное
   пойдёт не от беды, а от нашей же путаницы. Поэтому либо пара файлов
   из одного места, либо пробу не делаем вовсе и говорим об этом вслух.
   --------------------------------------------------------------------- */
const ПУТЬ_К_ВИДУ = path.join(path.dirname(ПУТЬ_К_ИГРЕ), '..', 'server', 'партия-по-сети.js');
let сеть = null;
let почемуБезВида = '';
if (fs.existsSync(ПУТЬ_К_ВИДУ)) {
  try {
    сеть = require(ПУТЬ_К_ВИДУ);
    if (typeof сеть.видДляИгрока !== 'function') {
      сеть = null;
      почемуБезВида = 'в ' + ПУТЬ_К_ВИДУ + ' нет «видДляИгрока»';
    }
  } catch (сбой) {
    сеть = null;
    почемуБезВида = 'не удалось поднять ' + ПУТЬ_К_ВИДУ + ': ' + сбой.message;
  }
} else {
  почемуБезВида = 'рядом с игрой нет server/партия-по-сети.js (' + ПУТЬ_К_ВИДУ + ')';
}

