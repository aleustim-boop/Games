/* =====================================================================
   ПРАВИЛА, ПОСЧИТАННЫЕ ЗАНОВО.

   Всё, что ниже, написано по словам правил и смотрит только на «сырое»
   состояние партии: чьи руки, что на столе, кто вышел. Ни одна из этих
   функций не спрашивает игру, что она думает, — иначе проверка снова
   стала бы согласием с кодом.
   ===================================================================== */

function имяКарты(к) { return к ? к.имя + к.масть : '—'; }

/** Бьёт ли карта карту: старше той же масти либо козырь по некозырю. */
function моёБьёт(чем, что, козырь) {
  if (чем.масть === что.масть) return чем.вес > что.вес;
  return чем.масть === козырь && что.масть !== козырь;
}

/** Кто ещё за столом. Список выбывших проверяется отдельно, после каждого подхода. */
function вИгре(партия, кто) {
  return (партия.выбывшие || []).indexOf(кто) === -1;
}

/** Обход круга от названного места по часовой стрелке; вышедших пропускаем. */
function круг(партия, откого) {
  const места = партия.игроки;
  const начало = Math.max(0, места.indexOf(откого));
  const ряд = [];
  for (let шаг = 0; шаг < места.length; шаг++) {
    const имя = места[(начало + шаг) % места.length];
    if (вИгре(партия, имя)) ряд.push(имя);
  }
  return ряд;
}

/** Напарник — сидящий через одного. Есть только в игре парами. */
function мойНапарник(партия, кто) {
  if (!партия.парами) return null;
  const место = партия.игроки.indexOf(кто);
  return место === -1 ? null : партия.игроки[(место + 2) % партия.игроки.length];
}

function сторона(партия, кто, другой) {
  return кто === другой || мойНапарник(партия, кто) === другой;
}

/** Кто отбивался бы, если бы нападал названный игрок (парами — своему не ходят). */
function ктоОтбилсяБы(партия, нападающий) {
  for (const имя of круг(партия, нападающий)) {
    if (имя === нападающий) continue;
    if (партия.парами && сторона(партия, нападающий, имя)) continue;
    return имя;
  }
  return нападающий;    // за столом больше никого — партия уже кончена
}

/** Кто отбивается сейчас. */
function мойЗащитник(партия) {
  return ктоОтбилсяБы(партия, партия.атакует);
}

/** Что происходит за столом. Считаем по столу, а не спрашиваем игру. */
function мояФаза(партия) {
  if (партия.завершена) return 'конец';
  if (партия.стол.length === 0) return 'атака';
  if (партия.берёт) return 'докидывание';
  for (const пара of партия.стол) if (!пара.защита) return 'защита';
  return 'подкидывание';
}

function мойНеотбитых(партия) {
  let счёт = 0;
  for (const пара of партия.стол) if (!пара.защита) счёт++;
  return счёт;
}

/** Достоинства, лежащие на столе: только ими и подкидывают. */
function моиДостоинства(партия) {
  const набор = new Set();
  for (const пара of партия.стол) {
    набор.add(пара.атака.имя);
    if (пара.защита) набор.add(пара.защита.имя);
  }
  return набор;
}

/**
 * Разрешают ли правила положить эту карту в атаку прямо сейчас
 * (про очередь здесь ни слова — только про саму карту и про стол).
 *
 * Три ограничения, и все три из живой игры:
 *   • подкидывают только тем достоинством, что уже лежит на столе;
 *   • за подход кладут не больше шести карт;
 *   • неотбитых карт не может быть больше, чем карт в руке у того,
 *     кто отбивается, — иначе крыть ему физически нечем.
 */
function правилаПозволяютКарту(партия, карта) {
  const фаза = мояФаза(партия);
  if (фаза !== 'атака' && фаза !== 'подкидывание' && фаза !== 'докидывание') return false;
  if (партия.стол.length >= 6) return false;
  if (мойНеотбитых(партия) >= партия.руки[мойЗащитник(партия)].length) return false;
  if (фаза === 'атака') return true;
  return моиДостоинства(партия).has(карта.имя);
}

/**
 * Почему правила не дают положить эту карту — словами, для отчёта.
 * Пустая строка означает «дают».
 */
function почемуНельзяКарту(партия, карта) {
  const фаза = мояФаза(партия);
  if (фаза !== 'атака' && фаза !== 'подкидывание' && фаза !== 'докидывание') {
    return 'сейчас фаза «' + фаза + '»: пока карта на столе не отбита, не кладёт никто';
  }
  if (партия.стол.length >= 6) return 'на столе уже шесть карт — больше за подход не кладут';
  const защитник = мойЗащитник(партия);
  if (мойНеотбитых(партия) >= партия.руки[защитник].length) {
    return 'неотбитых карт ' + мойНеотбитых(партия) + ', а в руке у ' + защитник + ' всего ' +
      партия.руки[защитник].length + ' — крыть будет нечем';
  }
  if (фаза === 'атака') return '';
  if (!моиДостоинства(партия).has(карта.имя)) {
    return 'такого достоинства на столе нет (лежат ' + Array.from(моиДостоинства(партия)).join(',') + ')';
  }
  return '';
}

/** Кому вообще разрешено подкидывать в этом подходе и в каком порядке. */
function мойПорядокПодкидывающих(партия) {
  const защитник = мойЗащитник(партия);
  return круг(партия, партия.атакует).filter(function (имя) {
    if (имя === защитник) return false;
    if (партия.парами && сторона(партия, защитник, имя)) return false;   // напарнику не подкидывают
    return true;
  });
}

/** Найдётся ли у игрока хоть одна карта, которую правила разрешают положить. */
function естьЧемПодкинуть(партия, кто) {
  for (const карта of партия.руки[кто] || []) {
    if (правилаПозволяютКарту(партия, карта)) return true;
  }
  return false;
}

/**
 * ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА — кто вправе ПОЛОЖИТЬ карту прямо сейчас.
 * Пусто (null) означает: положить не вправе никто, остаётся только закрыть подход.
 *
 * Право идёт по кругу и по одному: начинает тот, кто ходил, дальше сосед
 * по часовой стрелке. Пропускаем двоих: того, кто уже сказал «больше
 * не подкидываю», и того, кому подкинуть просто нечем, — его ответ и так
 * известен по картам.
 *
 * ВАЖНО: сказавший «пас» из круга выбывает ДО КОНЦА ПОДХОДА. Он не получает
 * право положить карту обратно ни при каких обстоятельствах — даже если
 * у всех остальных карты кончились и спрашивать больше некого.
 *
 * «Спасовавших» проверка считает сама, своим списком (см. «спасовавшие»
 * в прогоне партии), и нарочно не подглядывает в поле «пасы» самой игры:
 * иначе она согласилась бы с любой ошибкой в этом поле.
 */
function ктоВправеКласть(партия, спасовавшие) {
  const фаза = мояФаза(партия);
  if (фаза === 'атака') return партия.атакует;      // первую карту кладёт только ходящий
  if (фаза !== 'подкидывание' && фаза !== 'докидывание') return null;
  for (const имя of мойПорядокПодкидывающих(партия)) {
    if (спасовавшие.has(имя)) continue;
    if (!естьЧемПодкинуть(партия, имя)) continue;
    return имя;
  }
  return null;
}

/**
 * Чьё сейчас слово — то есть от кого игра ждёт ответа.
 *
 * Слово и право положить карту — РАЗНЫЕ ВЕЩИ, и здесь проверка однажды
 * уже споткнулась. Когда подкинуть больше некому, слово всё равно кому-то
 * принадлежит: кто-то один должен сказать «Бито» и закрыть подход, иначе
 * стол так и будет лежать. Но это вернувшееся слово даёт право ТОЛЬКО
 * закрыть подход, а не положить карту.
 *
 * КОМУ ЖЕ ОНО ДОСТАЁТСЯ. Правило владельца короткое: сказал «больше
 * не подкидываю» — до конца подхода тебя не спрашивают больше ни о чём.
 * Значит, спасовавшего пропускают и здесь: подход закрывает ПЕРВЫЙ
 * ПО КРУГУ, КТО ЕЩЁ НЕ ОТКАЗЫВАЛСЯ. Обычно это тот, кому просто нечем
 * подкинуть: молчать он не отказывался, спросить его можно.
 *
 * ЗДЕСЬ ЭТА ПРОВЕРКА ОДНАЖДЫ УЖЕ ОШИБЛАСЬ, И ОШИБКА СТОИЛА ДОРОГО.
 * Раньше запасным ответом стоял «тот, кто ходил» — списанный у тогдашнего
 * кода игры. И вот что из этого вышло у живых людей: ходивший спасовал
 * ещё в подкидывании, подкидывал сосед, защитник сказал «Беру», подкинуть
 * стало нечем никому — и слово вернулось к спасовавшему. Класть карту он
 * не вправе, остаётся формально нажать «Пас» второй раз; а на его
 * телефоне была вчерашняя страница, где такому игроку кнопку не рисуют
 * вовсе. Партия встала совсем. Прогон молчал, потому что считал ровно так
 * же, как сломанная игра.
 *
 * Самый последний запасной ответ — тот, кто ходил. Он на случай, если
 * отказались вообще все: в живой партии такого не бывает (отказ
 * последнего сам закрывает подход), но слово должно быть у кого-то
 * всегда, иначе проверка не сможет даже назвать виноватого.
 */
function моёСлово(партия, спасовавшие) {
  const фаза = мояФаза(партия);
  if (фаза === 'конец') return null;
  if (фаза === 'защита') return мойЗащитник(партия);
  if (фаза === 'атака') return партия.атакует;
  const кладущий = ктоВправеКласть(партия, спасовавшие);
  if (кладущий) return кладущий;
  for (const имя of мойПорядокПодкидывающих(партия)) {
    if (!спасовавшие.has(имя)) return имя;   // подход закроет тот, кто ещё молчал
  }
  return партия.атакует;
}

/** Разрешает ли перевод правила переводного дурака. */
function правилаПозволяютПеревод(партия, карта) {
  if (!партия.переводной || !карта) return false;
  if (мояФаза(партия) !== 'защита') return false;
  // Перевести можно, только пока НИ ОДНА карта подхода не отбита:
  // покрыл хоть раз — признал подход своим.
  if (мойНеотбитых(партия) !== партия.стол.length) return false;
  if (партия.стол.length >= 6) return false;
  if (!моиДостоинства(партия).has(карта.имя)) return false;
  const защитник = мойЗащитник(партия);
  const следующий = ктоОтбилсяБы(партия, защитник);
  if (следующий === защитник) return false;                        // переводить некому
  return партия.руки[следующий].length >= партия.стол.length + 1;  // ему должно быть чем крыть
}

/* =====================================================================
   СЛЕПОК СОСТОЯНИЯ

   Пробный запрещённый ход может у сломанной игры пройти и что-нибудь
   передвинуть. Чтобы это не портило дальнейшую партию, перед пробами
   снимаем слепок и сразу после возвращаем всё назад. Карты в слепке —
   те же самые предметы, а не копии: иначе проверка «карта лежит сразу
   в двух местах» перестала бы работать.
   ===================================================================== */

function слепок(партия) {
  const руки = {};
  for (const имя of партия.игроки) руки[имя] = партия.руки[имя].slice();
  return {
    руки: руки,
    стол: партия.стол.map(function (п) { return { атака: п.атака, защита: п.защита }; }),
    отбой: партия.отбой.slice(),
    колода: партия.колода.slice(),
    атакует: партия.атакует,
    берёт: партия.берёт,
    пасы: (партия.пасы || []).slice(),
    выбывшие: (партия.выбывшие || []).slice(),
    завершена: партия.завершена,
    результат: партия.результат,
    проигравшие: (партия.проигравшие || []).slice()
  };
}

/**
 * Вернуть состояние как было.
 *
 * Списки чистим и наполняем НА МЕСТЕ, а не подменяем новыми. Разница
 * не косметическая: если подменить, то любая переменная, взятая до отката
 * («рука = партия.руки[защитник]»), продолжит указывать на брошенный
 * список — уже испорченный пробным ходом. Так эта проверка сама себя
 * и обманула на первом же запуске: считала карты по одному списку,
 * а игре называла номера из другого, и игра честно отказывала.
 */
function вернуть(партия, с) {
  const наполнить = function (список, чем) {
    список.length = 0;
    for (const э of чем) список.push(э);
    return список;
  };
  for (const имя of партия.игроки) наполнить(партия.руки[имя], с.руки[имя]);
  наполнить(партия.стол, с.стол.map(function (п) { return { атака: п.атака, защита: п.защита }; }));
  наполнить(партия.отбой, с.отбой);
  наполнить(партия.колода, с.колода);
  партия.атакует = с.атакует;
  партия.берёт = с.берёт;
  партия.пасы = с.пасы.slice();
  партия.выбывшие = с.выбывшие.slice();
  партия.завершена = с.завершена;
  партия.результат = с.результат;
  партия.проигравшие = с.проигравшие.slice();
}

/** Отличается ли состояние от слепка — коротким текстом, для отчёта. */
function чтоИзменилось(партия, с) {
  const беды = [];
  for (const имя of партия.игроки) {
    if (партия.руки[имя].length !== с.руки[имя].length) {
      беды.push('рука ' + имя + ': было ' + с.руки[имя].length + ', стало ' + партия.руки[имя].length);
    }
  }
  if (партия.стол.length !== с.стол.length) {
    беды.push('на столе: было ' + с.стол.length + ', стало ' + партия.стол.length);
  }
  if (партия.атакует !== с.атакует) беды.push('ходящий: был ' + с.атакует + ', стал ' + партия.атакует);
  return беды.join('; ');
}

/* =====================================================================
   ПРОВЕРКИ СОСТОЯНИЯ (то, что верно всегда)
   ===================================================================== */

function всеКарты(партия) {
  const список = [];
  for (const имя of партия.игроки) for (const к of партия.руки[имя]) список.push(к);
  for (const к of партия.колода) список.push(к);
  for (const к of партия.отбой) список.push(к);
  for (const пара of партия.стол) {
    список.push(пара.атака);
    if (пара.защита) список.push(пара.защита);
  }
  return список;
}

function проверитьСостояние(партия) {
  const беды = [];

  // 1. Карты не пропадают и не размножаются.
  const карты = всеКарты(партия);
  if (карты.length !== партия.размерКолоды) {
    беды.push('карт в партии ' + карты.length + ' вместо ' + партия.размерКолоды);
  }
  const виденные = new Set();
  for (const к of карты) {
    if (виденные.has(к)) { беды.push('карта ' + имяКарты(к) + ' лежит сразу в двух местах'); break; }
    виденные.add(к);
  }

  // 2. Стол: не больше шести пар, и каждая побитая карта побита по правилам.
  if (партия.стол.length > 6) беды.push('на столе ' + партия.стол.length + ' карт — больше шести');
  for (const пара of партия.стол) {
    if (пара.защита && !моёБьёт(пара.защита, пара.атака, партия.козырь)) {
      беды.push('карта ' + имяКарты(пара.атака) + ' побита неподходящей ' + имяКарты(пара.защита));
    }
  }

  // 3. Козырная карта лежит под колодой, пока колода не пуста.
  if (партия.колода.length > 0 && партия.колода[партия.колода.length - 1] !== партия.козырнаяКарта) {
    беды.push('козырная карта не лежит под колодой');
  }

  // 4. Пока в колоде есть карты, новый подход начинается с полными руками.
  if (!партия.завершена && партия.колода.length > 0 && партия.стол.length === 0) {
    for (const имя of партия.игроки) {
      if (вИгре(партия, имя) && партия.руки[имя].length < 6) {
        беды.push('колода не пуста (' + партия.колода.length + '), а рука ' + имя +
          ' недобрана: ' + партия.руки[имя].length);
      }
    }
  }

  // 5. Вышедшим из партии карты не полагаются, и выбыть можно только при пустой колоде.
  for (const имя of партия.выбывшие || []) {
    if (партия.руки[имя].length > 0) {
      беды.push('игрок ' + имя + ' объявлен вышедшим, а в руке у него ' + партия.руки[имя].length + ' карт');
    }
  }
  if ((партия.выбывшие || []).length > 0 && партия.колода.length > 0 && партия.стол.length === 0) {
    беды.push('кто-то вышел из партии, хотя в колоде ещё ' + партия.колода.length + ' карт');
  }

  // 6. Пока партия не окончена, слово обязано кому-то принадлежать.
  if (!партия.завершена && игра.ктоХодит(партия) === null) {
    беды.push('партия не окончена, а слова нет ни у кого — это зависание');
  }

  // 7. Конец партии: дурак определён по правилам.
  if (партия.завершена) {
    if (партия.стол.length > 0) беды.push('партия окончена, а на столе остались карты');
    if (партия.колода.length > 0) беды.push('партия окончена, а в колоде ещё ' + партия.колода.length + ' карт');
    const сКартами = партия.игроки.filter(function (имя) { return партия.руки[имя].length > 0; });
    let ожидаются;
    if (партия.парами) {
      // Дурак — не человек, а пара: проигрывает та пара, у которой остались карты.
      const парыСтола = [
        [партия.игроки[0], партия.игроки[2]],
        [партия.игроки[1], партия.игроки[3]]
      ];
      const проигравшиеПары = парыСтола.filter(function (пара) {
        return пара.some(function (имя) { return партия.руки[имя].length > 0; });
      });
      ожидаются = проигравшиеПары.length === 1 ? проигравшиеПары[0].slice() : [];
    } else {
      ожидаются = сКартами.slice();
    }
    const записаны = (партия.проигравшие || []).slice().sort().join(',');
    if (записаны !== ожидаются.slice().sort().join(',')) {
      беды.push('дурак назван неверно: записано «' + (записаны || 'никто') +
        '», а по рукам выходит «' + (ожидаются.join(',') || 'ничья') + '»');
    }
    if (!партия.парами && сКартами.length > 1) {
      беды.push('партия окончена, а карты остались сразу у ' + сКартами.length + ' игроков');
    }
  }

  return беды;
}

/** Что игра думает о фазе и защитнике — обязано совпадать с правилами. */
function проверитьРазметку(партия) {
  const беды = [];
  if (партия.завершена) return беды;
  if (игра.фаза(партия) !== мояФаза(партия)) {
    беды.push('игра считает фазой «' + игра.фаза(партия) + '», а по столу это «' + мояФаза(партия) + '»');
  }
  if (игра.защищается(партия) !== мойЗащитник(партия)) {
    беды.push('игра отбиваться зовёт «' + игра.защищается(партия) +
      '», а по кругу отбивается «' + мойЗащитник(партия) + '»');
  }
  return беды;
}

/* =====================================================================
   КОНЕЦ ПОДХОДА, ПОСЧИТАННЫЙ ЗАНОВО

   Подход кончился — за один миг случается сразу многое: карты уходят
   в отбой или в руку тому, кто взял; все добирают из колоды; кто остался
   без карт при пустой колоде, выходит из партии; ход переходит к новому
   игроку. Каждое из этих действий — правило, и каждое можно посчитать
   самому, зная только, как было до.

   Считаем ровно так, как рассказали бы правила живому человеку:
     • взял — все карты со стола идут ему в руку; отбился — в отбой;
     • добирают до шести по кругу: первым тот, кто ходил, отбивавшийся
       последним, — и только пока в колоде есть карты;
     • колода пуста и рука пуста — игрок выходит из-за стола;
     • отбился — ходит он сам; взял — ход идёт дальше по кругу через него,
       а в игре парами остаётся у нападавшей пары (ходит напарник).
   ===================================================================== */

/** Собрать из слепка «партию, какой она была» — только для расчётов. */
function какБыло(партия, с) {
  return {
    игроки: партия.игроки,
    парами: партия.парами,
    переводной: партия.переводной,
    козырь: партия.козырь,
    руки: с.руки,
    стол: с.стол,
    колода: с.колода,
    отбой: с.отбой,
    атакует: с.атакует,
    берёт: с.берёт,
    выбывшие: с.выбывшие,
    завершена: с.завершена
  };
}

function проверитьЗавершениеПодхода(партия, с) {
  const беды = [];
  const было = какБыло(партия, с);
  const защитник = мойЗащитник(было);
  const взял = было.берёт;

  // 1. Куда ушли карты со стола.
  const ожидаемыеРуки = {};
  for (const имя of партия.игроки) ожидаемыеРуки[имя] = было.руки[имя].slice();
  let ожидаемыйОтбой = было.отбой.length;
  for (const пара of было.стол) {
    if (взял) {
      ожидаемыеРуки[защитник].push(пара.атака);
      if (пара.защита) ожидаемыеРуки[защитник].push(пара.защита);
    } else {
      ожидаемыйОтбой += пара.защита ? 2 : 1;
    }
  }

  // 2. Добор: по кругу от того, кто ходил, отбивавшийся — последним.
  const колода = было.колода.slice();
  const очередьДобора = круг(было, было.атакует)
    .filter(function (имя) { return имя !== защитник; })
    .concat([защитник]);
  for (const имя of очередьДобора) {
    while (ожидаемыеРуки[имя].length < 6 && колода.length > 0) ожидаемыеРуки[имя].push(колода.shift());
  }

  for (const имя of партия.игроки) {
    const стало = партия.руки[имя].map(имяКарты).slice().sort().join(',');
    const ждали = ожидаемыеРуки[имя].map(имяКарты).slice().sort().join(',');
    if (стало !== ждали) {
      беды.push('после подхода рука ' + имя + ' не такая, как по правилам: у игры «' +
        (стало || 'пусто') + '», по правилам «' + (ждали || 'пусто') + '»' +
        (взял ? ' (отбивавшийся ' + защитник + ' брал карты)' : ''));
      return беды;      // дальше сравнивать нечего: расклад уже разошёлся
    }
  }
  if (партия.колода.length !== колода.length) {
    беды.push('в колоде после добора ' + партия.колода.length + ' карт, а по правилам должно остаться ' + колода.length);
  }
  if (партия.отбой.length !== ожидаемыйОтбой) {
    беды.push('в отбое ' + партия.отбой.length + ' карт, а по правилам должно быть ' + ожидаемыйОтбой);
  }

  // 3. Кто вышел из партии: пустая рука при пустой колоде.
  const ожидаемыеВыбывшие = партия.игроки.filter(function (имя) {
    if (с.выбывшие.indexOf(имя) !== -1) return true;
    return колода.length === 0 && ожидаемыеРуки[имя].length === 0;
  });
  const выбылиУИгры = (партия.выбывшие || []).slice().sort().join(',');
  if (выбылиУИгры !== ожидаемыеВыбывшие.slice().sort().join(',')) {
    беды.push('из партии вышли «' + (выбылиУИгры || 'никто') + '», а по правилам должны были «' +
      (ожидаемыеВыбывшие.join(',') || 'никто') + '»');
  }

  /* 4. Кому достался ход.

     ЗДЕСЬ РАНЬШЕ ЖИЛА КОПИЯ ПРАВИЛА — и это была ошибка, вторая такая же
     за работу (первая была в замере итога: он держал свой счёт побед
     и мерил игру по нему). Копия выглядела так: «отбился — ходит сам;
     парами — ход напарнику нападавшего; наследник выбыл — ход его
     напарнику». Правило в игре починили (напарник нападавшего выбыл —
     очередь пары исчерпана, ход идёт дальше по кругу), а копия осталась
     старой и стала требовать от игры ровно ту ловушку, из-за которой
     живого игрока обходили: 447 ложных тревог в восьми парных раскладках
     при полностью чистых тридцати пяти непарных.

     ПОЧЕМУ НЕ «СПРОСИТЬ ПРАВИЛО У ИГРЫ». Так починен замер итога, и там
     это верно: он спрашивает «чем партия кончилась для меня» — тот самый
     ответ, который игра показывает человеку на экране, и сверять его надо
     именно с игрой. Здесь всё наоборот: под проверкой стоит САМО правило
     очереди. Спроси мы у игры, кому она отдала ход, и сверь с тем, кому
     она собиралась его отдать, — проверка сравнит игру с собой и согласится
     с любой будущей ошибкой. Такая проверка не стоит строчки, которую
     занимает.

     ЧТО ПРОВЕРЯЕМ ВМЕСТО ЭТОГО. Не «кто именно», а свойства, которым выбор
     обязан отвечать при любом правиле очереди. Они не устареют от новой
     правки, потому что не повторяют решения игры:
       • ход достался живому — не вышедшему из партии;
       • отбился — ходит он сам (это правило одинаково и вдвоём, и
         компанией, и парами; менять его никто не собирался);
       • взял — ход через него перешагивает: взявший не ходит сам.
         Взявший из партии не выходит никогда (он только что забрал
         карты), поэтому исключений здесь нет;
       • парами и взял — ход остаётся у нападавшей пары, ЛИБО напарник
         нападавшего уже вне игры. Нарочно «либо»: что делать во втором
         случае — это и есть починенное решение, и его проверка не
         повторяет. Зато «ход ни с того ни с сего улетел в чужую пару»
         поймается.

     А САМА СПРАВЕДЛИВОСТЬ ОЧЕРЕДИ проверяется отдельно и не здесь —
     см. «проверитьСправедливостьВПарах» (тот самый расклад, разложенный
     руками) и «проверитьСправедливостьОчереди» (случайные партии: кого
     бросили доигрывать зрителем). Ту беду ловят они, а не сверка
     «кто наследник». */
  if (!партия.завершена) {
    const наследник = партия.атакует;

    if (ожидаемыеВыбывшие.indexOf(наследник) !== -1) {
      беды.push('ход после подхода достался «' + наследник + '», а он вышел из партии ' +
        '(отбивавшийся ' + защитник + (взял ? ' взял карты' : ' отбился') + ')');
    }

    /* Отбился — ходит сам. С одной оговоркой, и она не про пары:
       отбиться можно последней картой и тут же выйти из партии.
       Вышедшему ход не отдают ни в каком режиме, поэтому спрашиваем
       только с того, кто после подхода остался за столом. */
    const защитникОстался = ожидаемыеВыбывшие.indexOf(защитник) === -1;
    if (!взял && защитникОстался && наследник !== защитник) {
      беды.push('отбившийся «' + защитник + '» остался за столом, значит обязан ходить сам, ' +
        'а ход достался «' + наследник + '»');
    }

    if (взял && наследник === защитник) {
      беды.push('«' + защитник + '» взял карты, значит ход через него перешагивает, ' +
        'а игра оставила ход ему же');
    }

    if (взял && партия.парами) {
      const напарникНападавшего = мойНапарник(было, было.атакует);
      const парНеИсчерпана = напарникНападавшего &&
        ожидаемыеВыбывшие.indexOf(напарникНападавшего) === -1;
      const своя = наследник === было.атакует || наследник === напарникНападавшего;
      if (парНеИсчерпана && !своя) {
        беды.push('парами: «' + защитник + '» взял карты, напарник нападавшего «' +
          напарникНападавшего + '» ещё в игре — ход обязан остаться у нападавшей пары, ' +
          'а достался «' + наследник + '»');
      }
    }
  }

  return беды;
}

/** Следующий за этим местом, кто ещё в партии. */
function следующийЖивой(партия, откого) {
  const ряд = круг(партия, откого);
  if (ряд.length === 0) return откого;
  return ряд[0] === откого ? (ряд[1] || откого) : ряд[0];
}

/* =====================================================================
   ПРОБНЫЕ ХОДЫ: сверка с двух сторон

   Все пробы делаются между настоящими ходами и откатываются. Ни один
   пробный ход не меняет ход партии — но каждый рассказывает, согласна ли
   игра с правилами.
   ===================================================================== */

/* Сколько пробных ходов сделано — печатаем в отчёте, чтобы было видно,
   что проверка вправду стучалась во все двери, а не просто молчала. */
const счётПроб = { запрещённых: 0, законных: 0, обещаний: 0, нажатий: 0, кнопок: 0 };

function пробы(партия, слово, спасовавшие) {
  const беды = [];
  const фаза = мояФаза(партия);
  if (фаза === 'конец') return беды;
  const до = слепок(партия);
  /* Право положить карту и право говорить — разные вещи: спасовавшему
     слово может вернуться, чтобы закрыть подход, но класть карту он
     уже не вправе. Пробы спрашивают именно про право положить. */
  const кладущий = ктоВправеКласть(партия, спасовавшие);

  /* ---- Сторона первая: игра позволила запрещённое ---- */

  for (const кто of партия.игроки) {
    if (!вИгре(партия, кто)) continue;
    const рука = партия.руки[кто];
    for (let i = рука.length - 1; i >= 0; i--) {
      const карта = рука[i];
      const этоЕгоПраво = кто === кладущий;
      const картаЗаконна = правилаПозволяютКарту(партия, карта);
      // Класть карту вправе только тот, чья сейчас очередь, и только законную.
      if (этоЕгоПраво && картаЗаконна) continue;
      счётПроб.запрещённых++;
      if (игра.положитьВАтаку(партия, кто, i) === true) {
        let причина;
        if (этоЕгоПраво) {
          причина = 'карта ' + имяКарты(карта) + ' по правилам не кладётся: ' + почемуНельзяКарту(партия, карта);
        } else if (фаза === 'защита') {
          причина = 'пока карта на столе не отбита, класть не может никто, а игра пустила';
        } else if (спасовавшие.has(кто)) {
          причина = 'он уже сказал «больше не подкидываю» — до конца подхода это отказ, ' +
            'а игра дала ему положить карту снова' +
            (кладущий ? ' (очередь была у «' + кладущий + '»)' : ' (подкидывать было уже некому, оставалось закрыть подход)');
        } else {
          причина = 'очередь класть карту сейчас у «' + (кладущий || 'никого') + '», а игра пустила его вне очереди';
        }
        беды.push('игрок ' + кто + ' положил ' + имяКарты(карта) + ': ' + причина);
        вернуть(партия, до);
        return беды;      // одного примера довольно: дальше состояние уже не то
      }
    }
  }

  // «Больше не подкидываю» тоже говорят по очереди: чужой отказ сдвинул бы круг.
  if (фаза === 'подкидывание' || фаза === 'докидывание') {
    for (const кто of партия.игроки) {
      if (кто === слово || !вИгре(партия, кто)) continue;
      счётПроб.запрещённых++;
      if (игра.пас(партия, кто) === true) {
        беды.push('игрок ' + кто + ' сказал «больше не подкидываю» вне очереди (слово у «' + слово + '»)');
        вернуть(партия, до);
        return беды;
      }
    }
  }

  /* «Бито» посреди защиты. Пока на столе лежит неотбитая карта, подход
     закончить нельзя никому — ни тому, кто ходил, ни соседям: сначала
     защитник обязан ответить, отбиться ему или брать. */
  if (фаза === 'защита') {
    for (const кто of партия.игроки) {
      if (!вИгре(партия, кто)) continue;
      счётПроб.запрещённых++;
      if (игра.пас(партия, кто) === true) {
        беды.push('игрок ' + кто + ' закончил подход, пока на столе лежит неотбитая карта');
        вернуть(партия, до);
        return беды;
      }
    }
  }

  /* «Беру» не в свою пору. Сказать «беру» может только тот, кто сейчас
     отбивается, и только пока идёт защита: после этого карты уже разошлись
     по правилам подхода. */
  if (фаза !== 'защита') {
    счётПроб.запрещённых++;
    if (игра.объявитьБеру(партия) === true) {
      беды.push('в фазе «' + фаза + '» удалось сказать «Беру», хотя отбиваться уже не время');
      вернуть(партия, до);
      return беды;
    }
  }

  /* Бот, которого дёрнули не в его очередь, ходить не должен: очередь —
     это правило игры, а не вежливость отрисовки. */
  for (const кто of партия.игроки) {
    if (кто === слово || !вИгре(партия, кто)) continue;
    счётПроб.запрещённых++;
    игра.ходБота(партия, кто);
    const сдвинул = чтоИзменилось(партия, до);
    if (сдвинул) {
      беды.push('игру попросили сходить за «' + кто + '», хотя слово у «' + слово +
        '», — и она сходила: ' + сдвинул);
      вернуть(партия, до);
      return беды;
    }
  }

  // Перевод: запрещённый правилами — не должен проходить.
  if (фаза === 'защита' && партия.переводной) {
    const защитник = мойЗащитник(партия);
    const рука = партия.руки[защитник];
    for (let i = рука.length - 1; i >= 0; i--) {
      if (правилаПозволяютПеревод(партия, рука[i])) continue;
      счётПроб.запрещённых++;
      if (игра.перевести(партия, i) === true) {
        беды.push('игрок ' + защитник + ' перевёл картой ' + имяКарты(рука[i]) +
          ', хотя правила перевод здесь запрещают');
        вернуть(партия, до);
        return беды;
      }
    }
  }

  /* ---- Сторона вторая: игра запретила разрешённое ---- */

  if (фаза !== 'защита' && кладущий) {
    const рука = партия.руки[кладущий] || [];
    for (let i = рука.length - 1; i >= 0; i--) {
      if (!правилаПозволяютКарту(партия, рука[i])) continue;
      счётПроб.законных++;
      const легло = игра.положитьВАтаку(партия, кладущий, i);
      вернуть(партия, до);
      if (легло !== true) {
        беды.push('игра не дала ' + кладущий + ' положить ' + имяКарты(рука[i]) +
          ', хотя очередь его и карта законная');
        return беды;
      }
      break;      // хватит одной законной карты
    }
  }

  if (фаза === 'защита') {
    const защитник = мойЗащитник(партия);
    const рука = партия.руки[защитник];
    let проверено = false;
    for (let п = 0; п < партия.стол.length && !проверено; п++) {
      if (партия.стол[п].защита) continue;
      for (let i = 0; i < рука.length; i++) {
        if (!моёБьёт(рука[i], партия.стол[п].атака, партия.козырь)) continue;
        счётПроб.законных++;
        const отбилось = игра.отбить(партия, п, i);
        вернуть(партия, до);
        if (отбилось !== true) {
          беды.push('игра не дала ' + защитник + ' отбить ' + имяКарты(партия.стол[п].атака) +
            ' картой ' + имяКарты(рука[i]) + ', хотя та бьёт');
          return беды;
        }
        проверено = true;
        break;
      }
    }
    if (партия.переводной) {
      for (let i = 0; i < рука.length; i++) {
        if (!правилаПозволяютПеревод(партия, рука[i])) continue;
        счётПроб.законных++;
        const перевелось = игра.перевести(партия, i);
        вернуть(партия, до);
        if (перевелось !== true) {
          беды.push('игра не дала ' + защитник + ' перевести картой ' + имяКарты(рука[i]) +
            ', хотя правила перевод разрешают');
          return беды;
        }
        break;
      }
    }
  }

  /* ---- Сторона третья: обещание против дела ---- */
  беды.push.apply(беды, пробаОбещания(партия, спасовавшие, до));
  if (беды.length) { вернуть(партия, до); return беды; }

  const сдвиг = чтоИзменилось(партия, до);
  if (сдвиг) {
    беды.push('пробные ходы сдвинули настоящую партию (' + сдвиг + ') — так быть не должно');
    вернуть(партия, до);
  }
  return беды;
}

/* =====================================================================
   ПРОБА «ОБЕЩАНИЕ ПРОТИВ ДЕЛА»

   Отдельный род беды, которого правила не ловят вовсе. Правила могут быть
   верны до последней запятой, а игрок всё равно застрянет: ему показали
   «можешь подкинуть», он тапнул карту — и получил отказ. Партия при этом
   не кончается: человек жмёт то, что ему предложили, и ничего не выходит.
   Так и случилось после нашей же починки очереди — сервер говорил
   «можешь», а правила отвечали «ты уже спасовал». Две партии из двадцати
   четырёх не доиграли.

   ОТКУДА БЕРЁТСЯ. Поле «могуПодкинуть» отвечает на разные вопросы
   в разных фазах: в подкидывании и докидывании оно значит «положи карту
   прямо сейчас», а в защите — «тебе подкидывать не запрещено вообще»
   (класть в защите нельзя никому). Про это в сервере есть предупреждение
   прямо в коде, но такое предупреждение живёт ровно до первого
   невнимательного читателя. Проба держит поле честным и тогда, когда комментарий
   уже не работает.

   ЧТО ИМЕННО ПРОВЕРЯЕМ. Одно утверждение, короткое:
       показано «можешь подкинуть» и есть карта, годная по столу
       ⇒ эта карта обязана лечь;
       не показано ⇒ не должна лечь ни одна.
   Годность карты считаем СВОЕЙ меркой («правилаПозволяютКарту»), а не
   спрашиваем у игры: спросишь у игры — снова получишь согласие с кодом,
   за что нас уже били дважды. Спрашиваем только в подкидывании
   и докидывании: в защите поле значит другое, и требовать от него
   обещания там значит выдумывать беду.

   Заодно сверяем две подписи, по которым игрок понимает, чей ход:
   «я хожу» и «я отбиваюсь». Их вид считает сам, а мы — своей меркой.

   ГРАНИЦЫ, И ИХ ВАЖНО ЗНАТЬ ДО ТОГО, КАК ОТМЕНЯТЬ СЕТЕВОЙ ПРОГОН.
   Эта проба зовёт сборку вида напрямую, минуя сервер и клиент. Значит:
     • она ходит по состояниям, которых сервер может и не создать,
       и наоборот — не видит тех, что рождаются только у него;
     • она не видит собственной жизни сервера: ожидания игроков в комнате,
       обрыва связи и возврата, ботов на местах ушедших, повторных
       отправок хода, чужих пропусков;
     • она ничего не знает о том, что рисует браузер: подсветку карт,
       кнопки «Бито» и «Беру».
   Поэтому tests/автопрогон-компанией.js с поднятым сервером она
   НЕ ЗАМЕНЯЕТ. Она снимает с него самый частый класс — расхождение
   «что игра разрешает» и «что игра показывает», — а всё остальное
   по-прежнему ловится только там.
   ===================================================================== */

function пробаОбещания(партия, спасовавшие, до) {
  const беды = [];
  if (!сеть) return беды;
  const фаза = мояФаза(партия);
  if (фаза === 'конец') return беды;

  const места = партия.игроки.map(function (имя) {
    return { ключ: имя, имя: имя, этоБот: имя !== 'человек', наСвязи: true };
  });
  const слово = моёСлово(партия, спасовавшие);
  const защитник = мойЗащитник(партия);

  for (const кто of партия.игроки) {
    if (!вИгре(партия, кто)) continue;
    let вид;
    try {
      вид = сеть.видДляИгрока(партия, кто, { места: места });
    } catch (сбой) {
      беды.push('сборка вида для игрока ' + кто + ' сорвалась: ' + сбой.message);
      return беды;
    }

    // Подписи «чей ход» игрок читает первыми — они обязаны совпадать с правилами.
    счётПроб.обещаний++;
    if (вид.яХожу !== (кто === слово)) {
      беды.push('игроку ' + кто + ' показано «' + (вид.яХожу ? 'ваш ход' : 'ход не ваш') +
        '», а по правилам слово у «' + слово + '»');
      return беды;
    }
    if (вид.яОтбиваюсь !== (кто === защитник)) {
      беды.push('игроку ' + кто + ' показано «' + (вид.яОтбиваюсь ? 'вы отбиваетесь' : 'вы не отбиваетесь') +
        '», а по правилам отбивается «' + защитник + '»');
      return беды;
    }

    /* Обещание «можешь подкинуть» спрашиваем только там, где оно и вправду
       обещание, — в подкидывании и докидывании. */
    if (фаза !== 'подкидывание' && фаза !== 'докидывание') continue;
    if (вид.могуПодкинуть === undefined) continue;

    // Есть ли у него карта, годную по столу — считаем сами.
    let естьГодная = false;
    for (const карта of партия.руки[кто]) {
      if (правилаПозволяютКарту(партия, карта)) { естьГодная = true; break; }
    }
    if (!естьГодная) continue;   // подкидывать нечем — обещание тут ни при чём

    // Ложится ли хоть одна такая карта на самом деле.
    let легла = false;
    for (let i = партия.руки[кто].length - 1; i >= 0; i--) {
      if (!правилаПозволяютКарту(партия, партия.руки[кто][i])) continue;
      счётПроб.обещаний++;
      if (игра.положитьВАтаку(партия, кто, i) === true) { легла = true; вернуть(партия, до); break; }
    }
    вернуть(партия, до);

    if (вид.могуПодкинуть && !легла) {
      беды.push('игроку ' + кто + ' показано «можешь подкинуть», а карта не ложится' +
        (спасовавшие.has(кто) ? ' (он уже сказал «больше не подкидываю»)' : '') +
        ': фаза «' + фаза + '», слово у «' + слово + '». Живой игрок тапнет карту и получит отказ');
      return беды;
    }
    if (!вид.могуПодкинуть && легла) {
      беды.push('игроку ' + кто + ' НЕ показано «можешь подкинуть», а карта ложится: ' +
        'фаза «' + фаза + '», слово у «' + слово + '». Игрок не увидит хода, который вправе сделать');
      return беды;
    }
  }
  return беды;
}

/* =====================================================================
   ПРОБА «А НАЖАТЬ-ТО ЕМУ ЧТО?»

   Вопрос, которого этот прогон не задавал ни разу за миллионы ходов.
   Он проверял многое: кому можно класть карту, чьё слово, что показано
   на экране. Но ни разу не спросил простого: у того, чьё сейчас слово,
   есть ли хоть ОДНО действие, которое вправду пройдёт? Если нет — партия
   мертва. Не «неудобна», не «непонятна», а мертва: ходить не может никто
   за столом, потому что все ждут одного человека, а тому нажать нечего.

   Спрашиваем ровно одно и самое дешёвое: у того, чьё слово, «Пас» обязан
   пройти. Почему именно «Пас», а не «положить карту»: положить бывает
   нечем законно (карт нужного достоинства нет — это не беда, это игра),
   а вот отказаться можно всегда. Отказ — последняя дверь; заперта она —
   заперты все.

   ЧЕСТНАЯ ГРАНИЦА ЭТОЙ ПРОБЫ. То самое зависание у живых игроков она
   не поймала бы: там «Пас» проходил, человеку просто оставалось нажать
   его второй раз, а на его вчерашней странице кнопки не было. Умирал
   экран, а не правила, и ловит это соседняя проба про кнопки. Замерено:
   на коде до починки эта проба не сработала ни разу из 56 тысяч.
   Держат её ради другого, куда более тяжёлого случая — когда стол мёртв
   по самим правилам и не спасает уже никакая страница. Проверено
   нарочной поломкой: 585 партий из 3200.

   Проба делается слепком и откатывается: настоящая партия от неё
   не сдвигается ни на шаг.
   ===================================================================== */

function пробаЕстьЧтоНажать(партия, слово, спасовавшие, до) {
  const беды = [];
  const фаза = мояФаза(партия);
  if (фаза !== 'подкидывание' && фаза !== 'докидывание') return беды;

  // Слово, отданное тому, кто уже встал из-за стола, — то же зависание.
  if (!вИгре(партия, слово)) {
    беды.push('слово отдано игроку «' + слово + '», а он уже вышел из партии: ' +
      'нажимать некому, за столом не сходит никто');
    return беды;
  }

  счётПроб.нажатий++;
  let прошёл;
  try {
    прошёл = игра.пас(партия, слово);
  } catch (сбой) {
    вернуть(партия, до);
    беды.push('игра сорвалась, когда «' + слово + '» сказал «Пас»: ' + сбой.message);
    return беды;
  }
  вернуть(партия, до);
  if (прошёл === true) return беды;

  // «Пас» не прошёл. Осталась ли у человека хоть карта, которую можно положить?
  const ложится = ляжетЛиХотьОднаКарта(партия, слово, до);
  беды.push('ЗАВИСАНИЕ: слово у «' + слово + '» (фаза «' + фаза + '», спасовали: ' +
    (Array.from(спасовавшие).join(',') || 'никто') + '), а «Пас» игра не приняла. ' +
    (ложится
      ? 'Положить карту он ещё может, но закончить подход — нет'
      : 'И ни одна карта у него не ложится: за столом не может сходить НИКТО'));
  return беды;
}

/* =====================================================================
   ПРОБА «КНОПКИ И ПОДСВЕТКА»

   Правила могут быть безупречны, а человек всё равно застрянет: на экране
   ему просто нечего нажать. Игра решает это ДВУМЯ РАЗНЫМИ МЕРКАМИ, и обе
   надо считать отдельно — застревают люди как раз там, где мерки разошлись.

     • КНОПКА КОНЦА ПОДХОДА («Пас», «Бито», «Готово»). Нынешняя страница
       показывает её тому, чьё слово. ВЧЕРАШНЯЯ страница показывала её
       только тому, кому вдобавок разрешено подкидывать.
     • ПОДСВЕТКА КАРТ. Карта светится зелёным, если слово моё и карту
       разрешает стол. Про отказ («я уже пасовал») подсветка не знает
       вовсе — отсюда и жалоба живого игрока: «карты светились, а класть
       не давало».

   ЗАЧЕМ СЧИТАТЬ СТАРУЮ МЕРКУ, если игру уже починили. Затем, что сервер
   обновляется мгновенно, а страница в телефоне у человека остаётся
   вчерашней, пока он её не перезагрузит. Зависание у живых игроков вылезло
   ровно на такой паре: новый сервер, старая страница. Правило, которое
   держится на том, что у всех свежий экран, — не правило.

   Поле «могуПодкинуть» считаем так же, как его собирает сервер: «класть
   разрешено» И «я ещё не отказывался». Это не подглядывание в код игры —
   это и есть тот кусок, который читает страница.
   ===================================================================== */

/** То самое поле «могуПодкинуть», которое сервер отдаёт странице. */
function полеМогуПодкинуть(партия, кто, спасовавшие) {
  if (typeof игра.можетПодкидывать !== 'function') return null;
  const спасовал = typeof игра.ужеСпасовал === 'function'
    ? игра.ужеСпасовал(партия, кто) === true
    : спасовавшие.has(кто);
  return игра.можетПодкидывать(партия, кто) === true && !спасовал;
}

/**
 * Ляжет ли у игрока хоть одна карта на самом деле. Пробуем и откатываем.
 *
 * Пробуем ВСЕ карты подряд, а не только те, что разрешают правила. Здесь
 * спрашивается не «прав ли он», а «сработает ли у него хоть одно нажатие»:
 * человеку, у которого экран мёртв, всё равно, законен ли ход, — ему важно,
 * чтобы хоть что-то произошло. А ход, который прошёл, хотя не должен был,
 * ловится отдельно, пробами запрещённого.
 */
function ляжетЛиХотьОднаКарта(партия, кто, до) {
  const рука = партия.руки[кто] || [];
  let легла = false;
  for (let i = рука.length - 1; i >= 0; i--) {
    if (игра.положитьВАтаку(партия, кто, i) === true) { легла = true; break; }
  }
  вернуть(партия, до);
  return легла;
}

function пробаКнопок(партия, слово, спасовавшие, до) {
  const беды = [];
  const фаза = мояФаза(партия);
  if (фаза !== 'подкидывание' && фаза !== 'докидывание') return беды;
  if (typeof игра.можноПоложить !== 'function') return беды;

  for (const кто of партия.игроки) {
    if (!вИгре(партия, кто)) continue;
    // Не его слово — экран у него пустой намеренно, ждать это не беда.
    if (кто !== слово) continue;

    счётПроб.кнопок++;
    const могуПодкинуть = полеМогуПодкинуть(партия, кто, спасовавшие);
    const ложится = ляжетЛиХотьОднаКарта(партия, кто, до);
    let светитсяКарта = false;
    for (const карта of партия.руки[кто] || []) {
      if (игра.можноПоложить(партия, карта) === true) { светитсяКарта = true; break; }
    }

    /* Вчерашняя страница: кнопки нет, потому что подкидывать нельзя,
       и ни одна карта не ложится. Нажать нечего совсем — стол мёртв. */
    if (могуПодкинуть === false && !ложится) {
      беды.push('ЗАВИСАНИЕ НА ВЧЕРАШНЕЙ СТРАНИЦЕ: слово у «' + кто + '» (фаза «' + фаза +
        '», спасовали: ' + (Array.from(спасовавшие).join(',') || 'никто') +
        '), но подкидывать ему уже нельзя — на старой странице кнопки конца подхода нет, ' +
        'и ни одна карта не ложится. Человеку, который не перезагружал страницу, нажать нечего');
      return беды;
    }

    /* Карта светится зелёным, а на деле не ложится: человек тапает
       и получает отказ. Партия при этом жива, но играть невозможно. */
    if (светитсяКарта && !ложится) {
      беды.push('игроку «' + кто + '» карты подсвечены как доступные, а положить не даёт ни одну' +
        (спасовавшие.has(кто) ? ' (он уже сказал «больше не подкидываю»)' : '') +
        ': фаза «' + фаза + '». Живой игрок тапает светящуюся карту и получает отказ');
      return беды;
    }
  }
  return беды;
}

/* =====================================================================
   ПРОБЫ НА ЗАВИСАНИЕ — ОТДЕЛЬНО ОТ ВСЕГО ОСТАЛЬНОГО

   Эти две пробы нарочно спрашивают игру, кому ОНА отдала слово, и дальше
   смотрят только на то, что этому человеку делать. Своей меркой «чьё слово»
   они не пользуются вовсе — и это важно по двум причинам.

   Первая: они отвечают на другой вопрос. «Слово отдали не тому» — это
   спор о правилах, а «нажать нечего» — это мёртвый стол. Второе тяжелее
   и для игрока заметнее, поэтому и спрашивается первым.

   Вторая: так они не зависят от того, права ли эта проверка насчёт очереди.
   Даже если завтра правило очереди поменяют и моя запись устареет, эти две
   пробы будут ловить зависание по-прежнему — они держатся не за правило,
   а за простой вопрос «есть ли живому человеку что нажать».
   ===================================================================== */

function пробыЗависания(партия, спасовавшие) {
  const беды = [];
  const фаза = мояФаза(партия);
  if (фаза !== 'подкидывание' && фаза !== 'докидывание') return беды;
  const словоИгры = игра.ктоХодит(партия);
  if (!словоИгры) return беды;      // «слова нет ни у кого» ловится отдельно
  const до = слепок(партия);

  беды.push.apply(беды, пробаЕстьЧтоНажать(партия, словоИгры, спасовавшие, до));
  if (беды.length) { вернуть(партия, до); return беды; }

  беды.push.apply(беды, пробаКнопок(партия, словоИгры, спасовавшие, до));
  вернуть(партия, до);
  return беды;
}

