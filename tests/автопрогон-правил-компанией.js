/**
 * Один блок отчёта: прогнать раскладку всеми игроками и напечатать итог.
 * Один и тот же код служит и полным раздачам, и концовкам — разница
 * только в том, кто собирает стол.
 */
function прогнатьИНапечатать(раскладка, заголовок, партий, картНаРуки, бедыДоПрогона) {
  const строки = [];
  let нарушений = (бедыДоПрогона || []).length;
  for (const т of (бедыДоПрогона || [])) строки.push('  * раздача: ' + т);
  let партийВсего = 0;
  let шаговВсего = 0;
  let самаяДлинная = 0;
  let зависших = 0;
  for (const игрок of ИГРОКИ) {
    const итог = прогонРаскладки(раскладка, игрок.ход, игрок.кличка, партий, картНаРуки);
    партийВсего += итог.сыграно;
    шаговВсего += итог.шагов;
    зависших += итог.зависших;
    for (const круг of итог.круги) {
      вечныеПартии.всего++;
      if (вечныеПартии.примеры.length < 4) вечныеПартии.примеры.push(заголовок + ' — ' + круг);
    }
    if (итог.самаяДлинная > самаяДлинная) самаяДлинная = итог.самаяДлинная;
    записатьИгрока(игрок.кличка, картНаРуки ? 'концовки' : 'полные раздачи', итог.сыграно, итог.сбои.length);
    нарушений += итог.сбои.length;
    for (const сбой of итог.сбои) {
      if (!сбой.журнал) continue;
      строки.push('  * ' + игрок.кличка + ', партия №' + сбой.номер + ':');
      for (const т of сбой.беды) строки.push('      - ' + т);
      строки.push('      последние ходы:');
      for (const ш of сбой.журнал) строки.push('        ' + ш);
    }
  }
  console.log('--- ' + заголовок + ' ---');
  console.log('  партий: ' + партийВсего + ', ходов за партию: в среднем ' +
    (партийВсего ? Math.round(шаговВсего / партийВсего) : 0) + ', самая длинная ' +
    самаяДлинная + ' (потолок ' + ПРЕДЕЛ_ХОДОВ + ')');
  if (нарушений === 0) {
    console.log('  нарушений и зависаний не найдено, все партии доиграны до конца\n');
  } else {
    console.log('  НАРУШЕНИЙ: ' + нарушений + (зависших ? ' (из них партий, упёршихся в потолок ходов: ' + зависших + ')' : ''));
    строки.forEach(function (с) { console.log(с); });
    console.log('');
  }
  return нарушений;
}

