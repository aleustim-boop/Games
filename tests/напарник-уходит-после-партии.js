'use strict';

/* =====================================================================
   НАПАРНИК, КОТОРЫЙ УХОДИТ ПОСЛЕ ПАРТИИ — инструмент тестировщика.

   Зачем. Обычный tests/полёт-от-игрока-по-сети.js после конца партии
   САМ соглашается на реванш («ещё»). Чтобы вручную в браузере проверить
   пункт «если кто-то вышел, стол возвращается в комнату» (экран 05),
   нужен ровно противоположный поступок: сыграть партию до конца и
   ЯВНО покинуть комнату (POST /выйти), как будто живой человек не стал
   играть дальше и закрыл игру. Тогда хозяин в браузере жмёт «Ещё
   партию» и тестировщик смотрит: стол вернулся в комнату? видна ли
   весть «ждём четвёртого»?

   Логика ходов скопирована из tests/полёт-от-игрока-по-сети.js (те же
   поля ответа сервера) — красиво играть не обязательно, обязательно
   дойти до конца партии.

   Запуск (сервер комнат уже поднят):
       node tests/напарник-уходит-после-партии.js 8796 КОД имя Аня
   ===================================================================== */

const http = require('http');

const ПОРТ = Number(process.argv[2]) || 8796;
const КОД_КОМНАТЫ = (process.argv[3] || '').toUpperCase();
const ХОЗЯИН = '127.0.0.1';

function довод(имяДовода, поУмолчанию) {
  const где = process.argv.indexOf(имяДовода);
  if (где === -1) return поУмолчанию;
  return process.argv[где + 1];
}

const МОЁ_ИМЯ = довод('имя', 'Уходящий') || 'Уходящий';
const ЖДЁМ_ДОЛГО = 40000;

function спросить(путь, тело, сколькоЖдать) {
  return new Promise((готово, беда) => {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length },
      timeout: сколькоЖдать || 15000
    }, (ответ) => {
      let текст = '';
      ответ.on('data', (ч) => { текст += ч; });
      ответ.on('end', () => {
        try { готово({ код: ответ.statusCode, тело: JSON.parse(текст || '{}') }); }
        catch (е) { готово({ код: ответ.statusCode, тело: { сырое: текст } }); }
      });
    });
    запрос.on('timeout', () => запрос.destroy(new Error('таймаут')));
    запрос.on('error', беда);
    запрос.end(данные);
  });
}

function бьёт(чем, что, козырь) {
  if (чем.масть === что.масть) return чем.вес > что.вес;
  return чем.масть === козырь && что.масть !== козырь;
}

function мелкая(рука, номера, козырь) {
  const некозырные = номера.filter((i) => рука[i].масть !== козырь);
  const из = некозырные.length ? некозырные : номера;
  return из.reduce((лучший, i) => (рука[i].вес < рука[лучший].вес ? i : лучший), из[0]);
}

function достоинстваНаСтоле(стол) {
  const набор = new Set();
  stolForEach(стол, (к) => набор.add(к.имя));
  return набор;
}
function stolForEach(стол, колбек) {
  стол.forEach((п) => { if (п.атака) колбек(п.атака); if (п.защита) колбек(п.защита); });
}

function popПробуемЗапасное(попытки) {
  попытки.push({ действие: 'бито' }, { действие: 'беру' });
}

function попыткиЗащиты(вид) {
  const рука = вид.мояРука || [];
  const стол = вид.стол || [];
  const козырь = вид.козырь;
  const попытки = [];

  const номерПары = стол.findIndex((п) => !п.защита);
  if (номерПары >= 0) {
    const атака = стол[номерПары].атака;
    const годные = [];
    рука.forEach((к, i) => { if (атака && бьёт(к, атака, козырь)) годные.push(i); });
    if (годные.length) {
      годные.sort((а, б) => рука[а].вес - рука[б].вес);
      годные.forEach((i) => попытки.push({ действие: 'отбить', пара: номерПары, карта: i }));
    }
  }
  popПробуемЗапасное(попытки);
  return попытки;
}

function решить(вид) {
  const рука = вид.мояРука || [];
  const стол = вид.стол || [];
  const козырь = вид.козырь;
  const яОтбиваюсь = вид.яОтбиваюсь !== undefined
    ? вид.яОтбиваюсь
    : Boolean(вид.яХожу && !вид.яАтакую);

  if (вид.яХожу && !яОтбиваюсь) {
    if (!рука.length) return стол.length ? { действие: 'бито' } : null;
    if (!стол.length) {
      const все = рука.map((к, i) => i);
      return { действие: 'ходить', карта: мелкая(рука, все, козырь) };
    }
    const достоинства = достоинстваНаСтоле(стол);
    const годные = [];
    рука.forEach((к, i) => { if (достоинства.has(к.имя)) годные.push(i); });
    if (годные.length) return { действие: 'ходить', карта: мелкая(рука, годные, козырь) };
    return { действие: 'бито' };
  }
  return null;
}

async function главная() {
  if (!КОД_КОМНАТЫ) throw new Error('не сказали код комнаты');
  const вход = await спросить('/войти', { код: КОД_КОМНАТЫ, имя: МОЁ_ИМЯ });
  if (вход.код !== 200 || !вход.тело.пропуск) {
    throw new Error('не пустили в комнату: ' + JSON.stringify(вход.тело));
  }
  const пропуск = вход.тело.пропуск;
  let вид = вход.тело.состояние;
  console.log('Вошёл в комнату ' + КОД_КОМНАТЫ + ' под именем «' + МОЁ_ИМЯ + '».');

  let версия = вид ? вид.версия : 0;
  let последнийХод = -1;

  for (;;) {
    if (вид && вид.завершена) {
      console.log('Партия кончилась — ухожу из комнаты (не соглашаюсь на реванш).');
      const выход = await спросить('/выйти', { код: КОД_КОМНАТЫ, пропуск }).catch((e) => ({ ошибка: e.message }));
      console.log('Ответ на /выйти: ' + JSON.stringify(выход.тело || выход));
      return;
    }
    if (вид && вид.яХожу && вид.номерСобытия !== последнийХод) {
      последнийХод = вид.номерСобытия;
      const яОтбиваюсь = вид.яОтбиваюсь !== undefined ? вид.яОтбиваюсь : Boolean(вид.яХожу && !вид.яАтакую);
      const попытки = яОтбиваюсь && !вид.берут ? попыткиЗащиты(вид) : (() => {
        const п = [];
        const намерение = решить(вид);
        if (намерение) п.push(намерение);
        popПробуемЗапасное(п);
        return п;
      })();
      for (const шаг of попытки) {
        const о = await спросить('/ход', Object.assign({ код: КОД_КОМНАТЫ, пропуск }, шаг)).catch(() => null);
        if (о && о.тело && о.тело.состояние) вид = о.тело.состояние;
        if (о && о.тело && о.тело.принято) break;
      }
      if (вид) версия = вид.версия;
      continue;
    }

    let ответ = null;
    try {
      ответ = await спросить('/что-нового', { код: КОД_КОМНАТЫ, пропуск, версия }, ЖДЁМ_ДОЛГО);
    } catch (сбой) {
      await new Promise((г) => setTimeout(г, 500));
      continue;
    }
    if (ответ.тело && ответ.тело.комнатыНет) {
      console.log('Комнату убрали — ухожу.');
      return;
    }
    if (ответ.тело && ответ.тело.состояние) {
      вид = ответ.тело.состояние;
      версия = вид.версия;
    }
  }
}

главная().catch((сбой) => {
  console.error('Сорвалось: ' + сбой.message);
  process.exitCode = 1;
});
