'use strict';

/* Проверка без браузера: лобби и итог партии шашек сделаны как у дурака
   (владелец 02.10: «все онлайн игры в одном стиле, эталон — дурак»).
   Читает разметку и код как текст.

   Запуск:  node tests/шашки-как-дурак.js [шашки.html] [шашки-лобби.js] [шашки-экран.js] [style-шашки.css]
   Пути нужны для «красного» запуска: проверка на КОПИЯХ, где поломку вернули
   (серия вместо места, нет «В меню» и т.п.), обязана упасть. Настоящие
   файлы портить нельзя.

   Ноль найденных узлов — провал, а не пропуск: каждая проверка сначала
   требует, чтобы нужный узел нашёлся. */

const fs = require('fs');
const path = require('path');

const корень = path.join(__dirname, '..');
function путь(номер, обычный) {
  return process.argv[номер] ? path.resolve(process.argv[номер]) : path.join(корень, обычный);
}
const путьHtml = путь(2, 'шашки.html');
const html = fs.readFileSync(путьHtml, 'utf8');
const лобби = fs.readFileSync(путь(3, 'игры/шашки/шашки-лобби.js'), 'utf8');
const экран = fs.readFileSync(путь(4, 'игры/шашки/шашки-экран.js'), 'utf8');
const стили = fs.readFileSync(путь(5, 'игры/шашки/style-шашки.css'), 'utf8');

let провалов = 0;
let всего = 0;
function проверить(условие, слова) {
  всего++;
  if (!условие) провалов++;
  console.log((условие ? '  ок      ' : '  ПРОВАЛ  ') + слова);
}

/** Кусок текста от начала до конца (включительно); пусто, если не нашли. */
function кусок(текст, начало, конец) {
  const от = текст.indexOf(начало);
  if (от === -1) return '';
  const до = текст.indexOf(конец, от);
  return до === -1 ? '' : текст.slice(от, до + конец.length);
}

console.log('Страница: ' + путьHtml);

// 1. Карточка профиля — место в рейтинге, не серия побед.
console.log('\n1. Карточка профиля');
const профиль = кусок(html, '<button id="лобби-профиль"', '</button>');
проверить(профиль.length > 0, 'карточка «лобби-профиль» найдена');
проверить(/id="лобби-аватар"/.test(профиль), 'аватар «лобби-аватар», как у дурака');
проверить(/id="лобби-рейтинг"[^>]*карточка-профиля__рейтинг--нет/.test(профиль), 'строка «лобби-рейтинг» с классом --нет (пока места нет)');
проверить(/id="лобби-место"/.test(профиль), 'в карточке есть узел «лобби-место»');
проверить(!/лобби-серия-текст/.test(html), 'узла серии «лобби-серия-текст» нет нигде в странице');
проверить(!/лобби-серия-текст/.test(лобби) && !/строкаСерии/.test(лобби), 'в игры/шашки/шашки-лобби.js серии побед нет');
проверить(/ЭкранРейтинга\.моёМесто\('шашки'\)/.test(лобби), 'место берётся тем же ходом, что у дурака: ЭкранРейтинга.моёМесто(\'шашки\')');
проверить(/карточка-профиля__рейтинг--нет/.test(лобби), 'код ставит/снимает класс --нет по наличию места');
проверить(/getElementById\('лобби-аватар'\)/.test(лобби), 'аватар в коде ищется по id «лобби-аватар»');

// 2. Картинка с подписью той же высоты.
console.log('\n2. Картинка-гнездо');
const картинка = кусок(html, '<figure class="лобби__картинка">', '</figure>');
проверить(картинка.length > 0, 'figure.лобби__картинка найдена');
const подпись = /<figcaption class="лобби__подпись">([^<]+)<\/figcaption>/.exec(картинка);
проверить(Boolean(подпись) && подпись[1].trim().length > 0, 'у картинки есть подпись figcaption.лобби__подпись' + (подпись ? ' («' + подпись[1].trim() + '»)' : ''));
проверить(стили.length > 0 && !/aspect-ratio:\s*876\s*\/\s*205/.test(стили), 'старой узкой панорамы 876/205 в style-шашки.css нет (рамка общая, 16:10)');

// 3. Карточки входов.
console.log('\n3. Карточки входов');
const онлайн = кусок(html, '<button id="лобби-найти-игру"', '</button>');
проверить(/карточка-входа__название">Играть онлайн</.test(онлайн), 'карточка онлайна — «Играть онлайн»');
const боты = кусок(html, '<button id="лобби-боты"', '</button>');
проверить(боты.length > 0, 'карточка «лобби-боты» найдена');
проверить(/карточка-входа__название">Играть с ботами</.test(боты), 'подпись карточки — «Играть с ботами»');
проверить(!/Играть с ботом</.test(боты), 'старой подписи «Играть с ботом» в карточке нет');
проверить(/Вдвоём на этом устройстве/.test(кусок(html, '<button id="лобби-вдвоём"', '</button>')), 'карточка «Вдвоём на этом устройстве» осталась');

// 4. Итог партии.
console.log('\n4. Итог партии');
const итог = кусок(html, '<section id="экран-итога"', '</section>');
проверить(итог.length > 0, 'секция «экран-итога» найдена');
for (const [id, слово] of [
  ['кнопка-ещё', 'Играть ещё'], ['кнопка-реванш', 'Реванш'], ['кнопка-ещё-с-ботом', 'Сыграть с ботом'],
  ['кнопка-похвастаться', 'Похвастаться'], ['кнопка-рекорды-итог', 'Рекорды'], ['кнопка-в-меню-итог', 'В меню']
]) {
  const кнопка = кусок(итог, '<button id="' + id + '"', '</button>');
  проверить(кнопка.length > 0 && кнопка.indexOf('>' + слово + '<') !== -1, 'на итоге есть «' + слово + '» (id ' + id + ')');
}
проверить(!/class="[^"]*скрыт[^"]*"[^>]*>В меню</.test(кусок(итог, '<button id="кнопка-в-меню-итог"', '</button>')), '«В меню» не спрятана в разметке (видна всегда)');
проверить(/<p id="итог-рейтинга"/.test(итог), 'строка «итог-рейтинга» на месте');
проверить(/<p id="подпись-реванша"/.test(итог), 'подпись реванша на месте');
проверить(/ОчкиРейтинга\.словаИтога\(/.test(экран), 'строка рейтинга пишется через ОчкиРейтинга.словаИтога');
проверить(/getElementById\('кнопка-реванш'\)/.test(экран) && /кнопкаРеванш\.addEventListener\('click', кликРеванш\)/.test(экран), 'реванш берётся из разметки и привязан к клику');
проверить(/кнопкаВМенюИтог\.addEventListener\('click'/.test(экран), '«В меню» на итоге привязана в игры/шашки/шашки-экран.js');
проверить(/ШашкиПохвастаться\.показать\(/.test(экран), '«Похвастаться» показывается кодом итога (игры/шашки/шашки-экран.js)');

// 5. Подключения на странице.
console.log('\n5. Подключения');
проверить(/<script src="общее\/js\/очки-рейтинга\.js/.test(html), 'общее/js/очки-рейтинга.js подключён');
проверить(/<script src="общее\/js\/похвастаться\.js/.test(html), 'общее/js/похвастаться.js подключён');

console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
process.exit(провалов === 0 ? 0 : 1);
