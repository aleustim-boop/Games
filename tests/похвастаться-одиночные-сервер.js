function ссылка(метка) { return НАЧАЛО + (метка ? '?startapp=' + метка : ''); }
function победа(игра, метка, мера, значение, режим) {
  const тело = { ссылка: ссылка(метка), игра: игра, исход: 'победа', мера: мера, значение: значение };
  if (режим !== undefined) тело.режим = режим;
  return тело;
}
function текст(тело) {
  const с = сервер.сообщениеОПобеде(тело, 1);
  return с ? с.текст : null;
}

