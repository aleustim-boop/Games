/* =====================================================================
   Проверка штаб/онлайн-страница.js (страница дашборда «Онлайн») и её
   подключения в штаб/дашборд.js.
   Задание: штаб/план-онлайн-дашборд.md, разделы «Главное» и «Этап 4».

   Сервер комнат здесь ПОДДЕЛЬНЫЙ — обычный http.createServer на
   свободном порту (не 8790, 8791, 8080 — боевые), а не настоящий
   server/сервер.js. Проверяется только страница дашборда: правильно ли
   она закрывает саму себя от туннеля, ходит ли она к серверу с верным
   заголовком-ключом и честно ли говорит, когда сервер молчит.

   Ключ читается модулем из файла server/данные/ключ-штаба тем же
   способом, что и настоящий сервер (server/папка-данных.js), поэтому
   его подменяют так же, как в других проверках — переменной окружения
   ДАННЫЕ_ИГРЫ на свою временную папку.

   Сценарии обычного прогона:
     1. Поддельный сервер с верным ключом отдаёт сводку → /онлайн 200,
        в HTML есть имя человека из «сейчас» и число «Сейчас онлайн: 1».
     2. Запрос с заголовком cf-connecting-ip → 403, и до сервера дело
        не доходит вовсе (счётчик запросов на подделке не растёт).
     3. Порт, где никто не слушает (сервер выключён) → 200, в тексте
        честно написано «сервер не отвечает».
     4. Сервер отвечает, но не тем ключом (403 от него) → тоже 200 у
        дашборда и то же честное «сервер не отвечает».
     5. Файла с ключом нет вовсе → 200, честный текст, к сети дело тоже
        не доходит.
     6. В HTML ни при одном сценарии нет самого значения ключа.
     7. Порт можно взять из переменной окружения ПОРТ_СЕРВЕРА_КОМНАТ, а
        не только явным доводом.
     8. Кнопка «Онлайн» — ссылка на /онлайн с понятным текстом.
     9. Дашборд действительно подключает модуль: require, маршрут
        GET /онлайн и кнопка на главной прописаны в штаб/дашборд.js
        (сам дашборд 8791 при этом не запускается — только текст файла).

   Ломающий запуск --сломать: копия штаб/онлайн-страница.js, в которой
   проверка заголовков туннеля всегда врёт «запрос свой» — сценарий 2
   обязан покраснеть.

   Запуск:
       node tests/онлайн-страница.js
       node tests/онлайн-страница.js --сломать
   ===================================================================== */

const path = require('path');
const os = require('os');
const fs = require('fs');
const http = require('http');
const crypto = require('crypto');

const СЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;
const КОРЕНЬ = path.join(__dirname, '..');
const ИСХОДНИК = path.join(КОРЕНЬ, 'штаб', 'онлайн-страница.js');
const ФАЙЛ_ДАШБОРДА = path.join(КОРЕНЬ, 'штаб', 'дашборд.js');

/* --- Мелкая обвязка проверок — тем же приёмом, что в других проверках проекта. --- */
function новыйПрогон() {
  const провалы = [];
  let проверок = 0;
  const провалыПоСценариям = {};
  let текущийСценарий = 0;

  function сценарий(н) { текущийСценарий = н; }
  function проверить(условие, что) {
    проверок++;
    if (!условие) {
      провалы.push('[' + текущийСценарий + '] ' + что);
      провалыПоСценариям[текущийСценарий] = (провалыПоСценариям[текущийСценарий] || 0) + 1;
      console.log('  ✗ [' + текущийСценарий + '] ' + что);
    } else {
      console.log('  ✓ [' + текущийСценарий + '] ' + что);
    }
  }
  return { сценарий, проверить, провалы, провалыПоСценариям, счёт: () => проверок };
}

/* --- Временные папки и переменные окружения — убираются за собой. --- */
const ВРЕМЕННЫЕ_ПАПКИ = [];
function свояВременнаяПапка(префикс) {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), префикс + '-'));
  ВРЕМЕННЫЕ_ПАПКИ.push(папка);
  return папка;
}
process.on('exit', function () {
  delete process.env.ДАННЫЕ_ИГРЫ;
  delete process.env.ПОРТ_СЕРВЕРА_КОМНАТ;
  for (const папка of ВРЕМЕННЫЕ_ПАПКИ) {
    try { fs.rmSync(папка, { recursive: true, force: true }); } catch (сбой) { /* не страшно */ }
  }
});

/** Свободный порт — попросить ОС и сразу отпустить. */
function свободныйПорт() {
  return new Promise(function (готово) {
    const сервер = http.createServer();
    сервер.listen(0, '127.0.0.1', function () {
      const порт = сервер.address().port;
      сервер.close(function () { готово(порт); });
    });
  });
}

/**
 * Поддельный сервер комнат: отвечает на GET /штаб-онлайн.
 *   режим 'ключ'  — отдаёт сводку, только если заголовок-ключ совпал;
 *   режим 'всегда403' — отказывает всем, как сервер с отличающимся ключом.
 * Считает число запросов — по нему видно, дошло ли дело до сети вообще.
 */
function поднятьПоддельныйСервер(имяЗаголовка, режим, ключ, сводка) {
  return new Promise(function (готово) {
    const сервер = http.createServer(function (запрос, ответ) {
      сервер.числоЗапросов += 1;
      const совпал = режим === 'ключ' && запрос.headers[имяЗаголовка] === ключ;
      if (!совпал) {
        ответ.writeHead(403, { 'Content-Type': 'application/json' });
        ответ.end(JSON.stringify({ ошибка: 'нет доступа' }));
        return;
      }
      ответ.writeHead(200, { 'Content-Type': 'application/json' });
      ответ.end(JSON.stringify(сводка));
    });
    сервер.числоЗапросов = 0;
    сервер.listen(0, '127.0.0.1', function () { готово(сервер); });
  });
}

const ПОДДЕЛЬНАЯ_СВОДКА = {
  сейчас: [{ номер: '900001', имя: 'Аня', игра: 'дурак', минут: 5 }],
  сегодня: [{ номер: '900001', имя: 'Аня', заходов: 1, минут: 5, минутыПоИграм: { дурак: 5 } }],
  неделя: [{ номер: '900001', имя: 'Аня', заходов: 1, минут: 5, минутыПоИграм: { дурак: 5 } }]
};

/* --- Весь набор сценариев 1-8: своей копии модуля не требует. --- */
async function прогонОсновной(модуль, прогон) {
  const { сценарий, проверить } = прогон;
  const ключ = crypto.randomBytes(16).toString('hex');

  const папкаСКлючом = свояВременнаяПапка('онлайн-страница-ключ');
  fs.writeFileSync(path.join(папкаСКлючом, 'ключ-штаба'), ключ + '\n', 'utf8');

  const серверСКлючом = await поднятьПоддельныйСервер(модуль.ЗАГОЛОВОК_КЛЮЧА_ШТАБА, 'ключ', ключ, ПОДДЕЛЬНАЯ_СВОДКА);
  const серверВсегда403 = await поднятьПоддельныйСервер(модуль.ЗАГОЛОВОК_КЛЮЧА_ШТАБА, 'всегда403', ключ, ПОДДЕЛЬНАЯ_СВОДКА);
  const пустойПорт = await свободныйПорт(); // никто не слушает

  process.env.ДАННЫЕ_ИГРЫ = папкаСКлючом;

  /* 1. Верный ключ — сводка приходит, в HTML есть имя и число «сейчас». */
  сценарий(1);
  {
    const итог = await модуль.страница({ headers: {} }, { порт: серверСКлючом.address().port });
    проверить(итог.код === 200, 'ответ 200 (было: ' + итог.код + ')');
    проверить(итог.тело.indexOf('Аня') !== -1, 'в HTML есть имя человека из «сейчас»');
    проверить(итог.тело.indexOf('Сейчас онлайн: 1') !== -1, 'в HTML есть счётчик «Сейчас онлайн: 1»');
  }

  /* 2. Заголовок туннеля → 403, до сервера дело не доходит. */
  сценарий(2);
  {
    const запросовДо = серверСКлючом.числоЗапросов;
    const итог = await модуль.страница({ headers: { 'cf-connecting-ip': '1.2.3.4' } }, { порт: серверСКлючом.address().port });
    проверить(итог.код === 403, 'заголовок cf-connecting-ip даёт 403 (было: ' + итог.код + ')');
    проверить(серверСКлючом.числоЗапросов === запросовДо, 'до поддельного сервера комнат дело не дошло');
  }

  /* 3. Сервер выключен (порт свободен) → 200, честное «сервер не отвечает». */
  сценарий(3);
  {
    const итог = await модуль.страница({ headers: {} }, { порт: пустойПорт, таймаутМс: 800 });
    проверить(итог.код === 200, 'выключенный сервер всё равно отдаёт страницу (было: ' + итог.код + ')');
    проверить(итог.тело.indexOf('сервер не отвечает') !== -1, 'в тексте честно написано «сервер не отвечает»');
  }

  /* 4. Сервер отвечает, но ключ не подошёл (403 от него) — тоже честно. */
  сценарий(4);
  {
    const итог = await модуль.страница({ headers: {} }, { порт: серверВсегда403.address().port });
    проверить(итог.код === 200, 'отказ сервера комнат не роняет страницу дашборда (было: ' + итог.код + ')');
    проверить(итог.тело.indexOf('сервер не отвечает') !== -1, 'отказ сервера комнат тоже честно назван «сервер не отвечает»');
  }

  /* 5. Файла с ключом нет — честный текст, к сети не ходили. */
  сценарий(5);
  {
    const папкаБезКлюча = свояВременнаяПапка('онлайн-страница-без-ключа');
    process.env.ДАННЫЕ_ИГРЫ = папкаБезКлюча;
    const запросовДо = серверСКлючом.числоЗапросов;
    const итог = await модуль.страница({ headers: {} }, { порт: серверСКлючом.address().port });
    проверить(итог.код === 200, 'без файла ключа страница всё равно отдаётся (было: ' + итог.код + ')');
    проверить(итог.тело.indexOf('сервер не отвечает') !== -1 || итог.тело.indexOf('ключ') !== -1,
      'без файла ключа — честное пояснение на экране');
    проверить(серверСКлючом.числоЗапросов === запросовДо, 'без ключа к серверу комнат не обращались');
    process.env.ДАННЫЕ_ИГРЫ = папкаСКлючом; // вернуть на место для следующих сценариев
  }

  /* 6. Ни в одном из ответов выше нет самого значения ключа. */
  сценарий(6);
  {
    const итог = await модуль.страница({ headers: {} }, { порт: серверСКлючом.address().port });
    проверить(итог.тело.indexOf(ключ) === -1, 'значение ключа в HTML не встречается');
  }

  /* 7. Порт можно взять из переменной окружения, а не только доводом. */
  сценарий(7);
  {
    process.env.ПОРТ_СЕРВЕРА_КОМНАТ = String(серверСКлючом.address().port);
    const итог = await модуль.страница({ headers: {} });
    проверить(итог.код === 200 && итог.тело.indexOf('Аня') !== -1,
      'порт из переменной ПОРТ_СЕРВЕРА_КОМНАТ сработал без явного довода');
    delete process.env.ПОРТ_СЕРВЕРА_КОМНАТ;
  }

  /* 8. Кнопка на главную — ссылка на /онлайн с понятным текстом. */
  сценарий(8);
  {
    const html = модуль.кнопка();
    проверить(html.indexOf('href="/онлайн"') !== -1, 'кнопка ведёт на /онлайн');
    проверить(html.indexOf('Онлайн') !== -1, 'на кнопке написано «Онлайн»');
  }

  await new Promise(function (готово) { серверСКлючом.close(готово); });
  await new Promise(function (готово) { серверВсегда403.close(готово); });
}

/* 9. Подключение в дашборде — по тексту файла (сам дашборд 8791 не поднимаем). */
function прогонПодключения(прогон) {
  const { сценарий, проверить } = прогон;
  сценарий(9);
  const текст = fs.readFileSync(ФАЙЛ_ДАШБОРДА, 'utf8');
  проверить(/require\(['"]\.\/онлайн-страница\.js['"]\)/.test(текст), 'дашборд.js подключает онлайн-страница.js');
  проверить(/['"]\/онлайн['"]/.test(текст), 'в дашборд.js есть адрес /онлайн');
  проверить(/онлайн\.страница\(/.test(текст), 'дашборд.js вызывает онлайн.страница(...)');
  проверить(/онлайн\.кнопка\(\)/.test(текст), 'дашборд.js вставляет онлайн.кнопка() в данные для главной');
}

/**
 * Сделать копию штаб/онлайн-страница.js во временной папке с указанными
 * текстовыми заменами. Рядом кладутся './страница.js' (лёгкая заглушка —
 * настоящая тянет за собой сбор.js и git, это здесь не при чём) и
 * '../server/папка-данных.js' (настоящая копия — она простая и без
 * своих require), чтобы require внутри копии разрешился как обычно.
 */
function сделатьКопиюСЗаменами(замены, суффикс) {
  let текст = fs.readFileSync(ИСХОДНИК, 'utf8');
  for (const { откуда, куда } of замены) {
    const новыйТекст = текст.split(откуда).join(куда);
    if (новыйТекст === текст) {
      return { ошибка: 'поломка "' + суффикс + '" не применилась: не найден фрагмент ' + JSON.stringify(откуда.slice(0, 70)) + '…' };
    }
    текст = новыйТекст;
  }
  const корень = свояВременнаяПапка('онлайн-страница-сломать-' + суффикс);
  const штабДир = path.join(корень, 'штаб');
  const серверДир = path.join(корень, 'server');
  fs.mkdirSync(штабДир, { recursive: true });
  fs.mkdirSync(серверДир, { recursive: true });
  fs.writeFileSync(path.join(штабДир, 'страница.js'), "'use strict';\nmodule.exports = { ОФОРМЛЕНИЕ: '' };\n", 'utf8');
  fs.copyFileSync(path.join(КОРЕНЬ, 'server', 'папка-данных.js'), path.join(серверДир, 'папка-данных.js'));
  const файл = path.join(штабДир, 'онлайн-страница.js');
  fs.writeFileSync(файл, текст, 'utf8');
  return { путь: файл };
}

const ЛОМАЮЩИЕ_ВАРИАНТЫ = [
  {
    имя: 'без-проверки-заголовков',
    поясн: 'проверка заголовков туннеля всегда говорит «запрос свой» — cf-connecting-ip больше не даёт 403 (сценарий 2)',
    ожидаемые: [2],
    замены: [
      {
        откуда: 'return ЗАГОЛОВКИ_ТУННЕЛЯ.some(function (имя) { return заголовки[имя] !== undefined; });',
        куда: 'return false;'
      }
    ]
  }
];

/* Только сценарий 2 нужен ломающему запуску — остальные про честность
   текста и не про заголовки туннеля, гонять их без нужды незачем. */
async function прогонТолькоСценарий2(модуль, прогон) {
  const { сценарий, проверить } = прогон;
  const ключ = crypto.randomBytes(16).toString('hex');
  const папка = свояВременнаяПапка('онлайн-страница-сломать-данные');
  fs.writeFileSync(path.join(папка, 'ключ-штаба'), ключ + '\n', 'utf8');
  process.env.ДАННЫЕ_ИГРЫ = папка;

  const сервер = await поднятьПоддельныйСервер(модуль.ЗАГОЛОВОК_КЛЮЧА_ШТАБА, 'ключ', ключ, ПОДДЕЛЬНАЯ_СВОДКА);
  сценарий(2);
  const запросовДо = сервер.числоЗапросов;
  const итог = await модуль.страница({ headers: { 'cf-connecting-ip': '1.2.3.4' } }, { порт: сервер.address().port });
  проверить(итог.код === 403, 'заголовок cf-connecting-ip по-прежнему даёт 403 (было: ' + итог.код + ')');
  проверить(сервер.числоЗапросов === запросовДо, 'до поддельного сервера комнат дело не дошло');
  await new Promise(function (готово) { сервер.close(готово); });
}

async function основной() {
  console.log('=== Проверка штаб/онлайн-страница.js ===');

  if (!СЛОМАТЬ) {
    const прогон = новыйПрогон();
    console.log('\n--- Обычный прогон ---');
    await прогонОсновной(require(ИСХОДНИК), прогон);
    прогонПодключения(прогон);

    console.log('\nИтого проверок: ' + прогон.счёт() + ', провалов: ' + прогон.провалы.length);
    for (const беда of прогон.провалы) console.log('  - ' + беда);
    process.exit(прогон.провалы.length > 0 ? 1 : 0);
    return;
  }

  console.log('\n*** ЛОМАЮЩИЙ ЗАПУСК: копия без проверки заголовков туннеля ***');
  let итогКод = 0;
  for (const вариант of ЛОМАЮЩИЕ_ВАРИАНТЫ) {
    console.log('\n--- Вариант «' + вариант.имя + '»: ' + вариант.поясн + ' ---');
    const копия = сделатьКопиюСЗаменами(вариант.замены, вариант.имя);
    if (копия.ошибка) {
      console.log('  ✗ ' + копия.ошибка);
      итогКод = 1;
      continue;
    }
    const прогон = новыйПрогон();
    await прогонТолькоСценарий2(require(копия.путь), прогон);
    const непойманные = вариант.ожидаемые.filter(function (н) { return !(н in прогон.провалыПоСценариям); });
    if (непойманные.length > 0) {
      console.log('  ПРОВЕРКА СЛЕПАЯ: копия «' + вариант.имя + '» не покраснела в сценарии ' + непойманные.join(', '));
      итогКод = 1;
    } else {
      console.log('  копия «' + вариант.имя + '» покраснела как положено в сценарии ' + вариант.ожидаемые.join(', ') + ' — проверка рабочая');
    }
  }
  console.log('\nЛомающий запуск завершён, итоговый код: ' + итогКод +
    ' (провалы внутри копий — ожидаемые, это и значит «покраснела»)');
  process.exit(итогКод);
}

основной().catch(function (беда) {
  console.log('ПРОВЕРКА ОБОРВАЛАСЬ: ' + (беда && беда.message));
  console.log(беда && беда.stack);
  process.exit(1);
});
