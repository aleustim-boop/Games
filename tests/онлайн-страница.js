/** Ломающий вариант про заголовки: свой сервер с ключом + сценарий 2 целиком. */
async function прогонДляЛомающихЗаголовков(модуль, прогон) {
  const ключ = crypto.randomBytes(16).toString('hex');
  const папка = свояВременнаяПапка('онлайн-страница-сломать-заголовки');
  fs.writeFileSync(path.join(папка, 'ключ-штаба'), ключ + '\n', 'utf8');
  process.env.ДАННЫЕ_ИГРЫ = папка;

  const сервер = await поднятьПоддельныйСервер(модуль.ЗАГОЛОВОК_КЛЮЧА_ШТАБА, 'ключ', ключ, ПОДДЕЛЬНАЯ_СВОДКА);
  await прогонЗаголовковТуннеля(модуль, прогон, сервер);
  await new Promise(function (готово) { сервер.close(готово); });
}

/** Ломающий вариант про таймаут: свой ключ (чтобы дело дошло до сети) + сценарий 10 целиком. */
async function прогонДляЛомающегоТаймаута(модуль, прогон) {
  const ключ = crypto.randomBytes(16).toString('hex');
  const папка = свояВременнаяПапка('онлайн-страница-сломать-таймаут');
  fs.writeFileSync(path.join(папка, 'ключ-штаба'), ключ + '\n', 'utf8');
  process.env.ДАННЫЕ_ИГРЫ = папка;

  await прогонМолчащегоСервера(модуль, прогон);
}

