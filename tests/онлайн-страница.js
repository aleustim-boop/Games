/** «ЧЧ:ММ» местного времени — своим способом, не копией из модуля. */
function часМин(мс) { return new Date(мс).toTimeString().slice(0, 5); }

/**
 * Поддельный хаб: считает вызовы, запоминает присланные скрипты, отвечает
 * тем, что вернёт «поведение(номерВызова)» (значение, промис или бросок).
 */
function поддельныйХаб(поведение) {
  const хаб = { вызовов: 0, скрипты: [] };
  хаб.вызвать = function (скрипт) {
    хаб.вызовов += 1;
    хаб.скрипты.push(скрипт);
    return Promise.resolve().then(function () { return поведение(хаб.вызовов); });
  };
  return хаб;
}

function ответВМ(сводка) { return { вывод: 'ГОТОВО\n' + JSON.stringify(сводка) }; }

