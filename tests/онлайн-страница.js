    const прошло = Date.now() - началоМс;
    проверить(!итог && !!сбой, 'вечно «идущий» запуск обрывается ошибкой по сроку, результата нет' + (итог ? ' (пришёл результат: ' + итог.вывод + ')' : ''));
    проверить(прошло < 1500, 'уложились в срок 600 мс с небольшим запасом (прошло ' + прошло + ' мс)');
    проверить(опросов().length >= 3, 'опрос действительно шёл — иначе проверка срока ничего не значит (опросов: ' + опросов().length + ')');
    const последний = вызовы.length ? вызовы[вызовы.length - 1].через : 0;
    проверить(последний <= 700, 'после срока запросов к хабу уже нет: последний ушёл на ' + последний + ' мс из 600');

    // в) хаб отвечает как надо — результат доходит (без этого проверки выше могли краснеть по глупости)
    подменить(function (запись) {
      if (запись.метод === 'POST') return ответХаба(200, { id: 'запуск-2', status: 'running' });
      return ответХаба(200, { status: 'done', stdout: 'ГОТОВО\n{}', exit_code: 0 });
    });
    началоМс = Date.now();
    итог = null;
    try { итог = await вм.выполнитьСкрипт('машина', 'echo 1', { срокМс: 3000, шагМс: 20 }); } catch (беда) { итог = { вывод: 'ОШИБКА ' + беда.message }; }
