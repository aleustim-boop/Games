/* =====================================================================
   Проверка штаб/онлайн-страница.js (страница дашборда «Онлайн») и её
   подключения в штаб/дашборд.js.
   Задание: штаб/план-онлайн-дашборд.md, разделы «Главное» и «Этап 4».

   Сервер комнат здесь ПОДДЕЛЬНЫЙ — обычный http.createServer на
   свободном порту (не 8790, 8791, 8080 — боевые), а не настоящий
   server/сервер.js. Проверяется только страница дашборда: правильно ли
   она закрывает саму себя от туннеля, ходит ли она к серверу с верным
   заголовком-ключом и честно ли говорит, когда сервер молчит или врёт.

   Ключ читается модулем из файла server/данные/ключ-штаба тем же
   способом, что и настоящий сервер (server/папка-данных.js), поэтому
   его подменяют так же, как в других проверках — переменной окружения
   ДАННЫЕ_ИГРЫ на свою временную папку.

   Сценарии обычного прогона:
     1. Поддельный сервер с верным ключом отдаёт сводку → /онлайн 200,
        в HTML есть имя человека из «сейчас» и число «Сейчас онлайн: 1».
     2. Заголовок туннеля → 403, и до сервера дело не доходит вовсе.
        Перебираются ВСЕ четыре заголовка (cf-connecting-ip, cf-ray,
        x-forwarded-for, x-real-ip) — список жёстко прописан здесь же,
        а не взят из модуля, иначе поломка самого списка в модуле
        (убрали заголовок — и модуль о нём больше не знает) осталась бы
        незамеченной. Для каждого заголовка — два запроса: с обычным
        значением и с пустым (''), заголовок присутствует в обоих
        случаях — оба обязаны получить 403.
     3. Порт, где никто не слушает (сервер выключён) → 200, в тексте
        честно написано «сервер не отвечает».
     4. Сервер отвечает, но не тем ключом (403 от него) → тоже 200 у
        дашборда и то же честное «сервер не отвечает».
     5. Файла с ключом нет вовсе → 200, честный текст, к сети дело тоже
        не доходит.
     6. В HTML ни при одном сценарии нет самого значения ключа.
     7. Порт можно взять из переменной окружения ПОРТ_СЕРВЕРА_КОМНАТ, а
        не только явным доводом.
     8. Кнопка «Онлайн» — ссылка на /онлайн с понятным текстом.
     9. Дашборд действительно подключает модуль: require, маршрут
        GET /онлайн и кнопка на главной прописаны в штаб/дашборд.js
        (сам дашборд 8791 при этом не запускается — только текст файла).
    10. Сервер комнат принял соединение и молчит (не отвечает и не
        закрывает сокет) дольше срока ожидания — страница не должна
        зависнуть, а обязана честно ответить «сервер не отвечает» за
        разумное время. Срок ответа передаётся страницe явным доводом
        настройки.таймаутМс = 300 (ниже, константа
        МОЛЧАЩИЙ_ТАЙМАУТ_МС) — так тест не ждёт боевые 2500 мс по
        умолчанию (штаб/онлайн-страница.js, СРОК_ОТВЕТА_МС). Сам тест
        на такой случай защищён своим внешним пределом ожидания
        ВНЕШНИЙ_ПРЕДЕЛ_МС = 3000: если сломанная копия таймаут вообще не
        поддерживает и виснет навсегда, тест не повиснет вместе с ней,
        а сам сдастся и зафиксирует провал.
    11. Сервер отвечает 200, но телом — не JSON, а мусор → страница всё
        равно 200 с честным «сервер не отвечает», дашборд не падает.

   Ломающий запуск --сломать — три независимых копии штаб/онлайн-страница.js,
   каждая обязана покраснеть в своём сценарии:
     - «без-проверки-заголовков»  — проверка заголовков туннеля всегда
       отвечает «запрос свой» → сценарий 2 красный по всем заголовкам.
     - «без-x-real-ip-в-списке»   — из списка ЗАГОЛОВКИ_ТУННЕЛЯ убран
       один заголовок (x-real-ip, как в примере задания) → сценарий 2
       красный именно по нему, остальные три по-прежнему проходят.
     - «без-таймаута»             — у запроса к серверу комнат убран
       и timeout, и обработчик 'timeout' → молчащий сервер вешает
       страницу навсегда → сценарий 10 красный (тест это ловит своим
       внешним пределом, не зависая).

   Запуск:
       node tests/онлайн-страница.js
       node tests/онлайн-страница.js --сломать
   ===================================================================== */

