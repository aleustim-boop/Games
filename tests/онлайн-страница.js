/** Убрать номера так, как это сделал бы скрипт на ВМ (для подставного хаба). */
function безНомеров(значение) {
  if (Array.isArray(значение)) return значение.map(безНомеров);
  if (значение && typeof значение === 'object') {
    const итог = {};
    for (const поле of Object.keys(значение)) if (поле !== 'номер') итог[поле] = безНомеров(значение[поле]);
    return итог;
  }
  return значение;
}

