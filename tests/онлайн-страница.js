  const серверВсегда403 = await поднятьПоддельныйСервер(модуль.ЗАГОЛОВОК_КЛЮЧА_ШТАБА, 'всегда403', ключ, ПОДДЕЛЬНАЯ_СВОДКА);
  const пустойПорт = await свободныйПорт(); // никто не слушает

  process.env.ДАННЫЕ_ИГРЫ = папкаСКлючом;

  /* 1. Верный ключ — сводка приходит, в HTML есть имя и число «сейчас». */
  сценарий(1);
  {
    const итог = await модуль.страница({ headers: {} }, { порт: серверСКлючом.address().port });
    проверить(итог.код === 200, 'ответ 200 (было: ' + итог.код + ')');
    проверить(итог.тело.indexOf('Аня') !== -1, 'в HTML есть имя человека из «сейчас»');
    проверить(итог.тело.indexOf('Сейчас онлайн: 1') !== -1, 'в HTML есть счётчик «Сейчас онлайн: 1»');
  }

  /* 2. Все заголовки туннеля (+ пустое значение) → 403, до сервера дело не доходит. */
  await прогонЗаголовковТуннеля(модуль, прогон, серверСКлючом);

  /* 3. Сервер выключен (порт свободен) → 200, честное «сервер не отвечает». */
