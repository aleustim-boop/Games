  '    *) shift;;',
  '  esac',
  'done',
  // как у настоящего curl: значение -w с «@» — это имя файла, и его нет
  'case "$TEMPLATE" in @*) echo "curl: option -w: error encountered when reading a file" >&2; exit 2;; esac',
  'if [ "${HEADER#@}" != "$HEADER" ]; then GOT=$(cat "${HEADER#@}"); else GOT="$HEADER"; fi',
  'if [ "$FAKE_MODE" = "down" ]; then CODE=000',
