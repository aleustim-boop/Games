function сколькоРаз(текст, кусок) {
  let раз = 0;
  let с = текст.indexOf(кусок);
  while (с !== -1) { раз++; с = текст.indexOf(кусок, с + кусок.length); }
  return раз;
}

function ломающийРежим() {
  console.log('=== Ломающий запуск: каждая поломка обязана покраснеть ===');
  let покраснело = 0;
  ПОЛОМКИ.forEach(function (поломка, номер) {
    console.log('\nПоломка ' + (номер + 1) + ': ' + поломка.что);
    const текст = fs.readFileSync(path.join(КОРЕНЬ, поломка.файл), 'utf8');
    const раз = сколькоРаз(текст, поломка.было);
    if (раз !== 1) {
      console.log('  ПРОВАЛ место порчи в ' + поломка.файл + ' нашлось ' + раз + ' раз(а), а нужно ровно 1');
      return;
    }
    const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'вход-по-коду-игра-порча-'));
    try {
      const копия = path.join(папка, path.basename(поломка.файл));
      fs.writeFileSync(копия, текст.replace(поломка.было, поломка.стало));
      const запуск = spawnSync(process.execPath, [__filename, '--' + поломка.довод + '=' + копия],
        { encoding: 'utf8', timeout: 180000 });
      const вывод = (запуск.stdout || '') + (запуск.stderr || '');
      const итог = /Итого проверок: (\d+), провалов: (\d+)/.exec(вывод);
      const провалыКопии = итог ? Number(итог[2]) : 0;
      const красная = запуск.status === 1 && провалыКопии > 0;
      if (красная) покраснело++;
      console.log('  ' + (красная ? 'ок     покраснела' : 'ПРОВАЛ осталась зелёной') +
        ': ' + (итог ? итог[0] : 'итога нет') + ', код выхода ' + запуск.status);
      вывод.split('\n').filter(function (с) { return с.indexOf('ПРОВАЛ') !== -1; }).slice(0, 3)
        .forEach(function (с) { console.log('         ' + с.trim()); });
    } finally {
      fs.rmSync(папка, { recursive: true, force: true });
    }
  });
  console.log('\nПоломок: ' + ПОЛОМКИ.length + ', покраснело: ' + покраснело);
  process.exitCode = покраснело === ПОЛОМКИ.length ? 0 : 1;
}

if (process.argv.indexOf('--сломать') !== -1) ломающийРежим();
else главное();
