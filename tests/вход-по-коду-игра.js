/* ---------- 6. Мусор в поле «игра» ---------- */

async function случайМусор() {
  console.log('\n6. Мусор в поле «игра» — сервер не падает');
  /* Не строка — сверки нет, вход как у старой страницы. Длинная строка
     латиницей (5000 байт) влезает в предел тела запроса и доходит до
     сверки: это строка, но не игра стола — честный 403. Та же длина
     кириллицей — 10000 байт, больше предела тела сервера (8 КБ): сервер
     отвечает 400 ещё до сверки. В обоих случаях — не 500 и без места. */
  const ОПИСАНИЕ = {
    'пускает': 'пускает, как раньше',
    'другая-игра': '403 «другая-игра», не 500',
    'велико': '400 «слишком большой запрос», не 500'
  };
  const случаи = [
    { что: 'объект', игра: { игра: 'шашки' }, ждём: 'пускает' },
    { что: 'массив', игра: ['шашки'], ждём: 'пускает' },
    { что: 'null', игра: null, ждём: 'пускает' },
    { что: 'строка в 5000 знаков латиницей', игра: 'x'.repeat(5000), ждём: 'другая-игра' },
    { что: 'строка в 5000 знаков кириллицей', игра: 'ш'.repeat(5000), ждём: 'велико' }
  ];
  let номер = 4001;
  for (const случай of случаи) {
    const стол = await создать(номер++, 'шашки');
    const вход = await войти(стол.данные.код, номер++, случай.игра);
    const вышло = {
      'пускает': вход.номер === 200 && Boolean(вход.данные.пропуск),
      'другая-игра': вход.номер === 403 && вход.данные.почему === 'другая-игра',
      'велико': вход.номер === 400 && !вход.данные.пропуск
    };
    проверить('6) ' + случай.что + ': ' + ОПИСАНИЕ[случай.ждём],
      стол.номер === 200 && вышло[случай.ждём], кратко(вход));
  }
}

