function поднятьСтраницу(играСтраницы, номер) {
  const страница = { узлы: new Map() };
  for (const id of УЗЛЫ_СТРАНИЦЫ) страница.узлы.set(id, сделатьУзел(id, страница));
  const запросы = [];
  const чужиеАдреса = [];
  const мост = { видов: 0 };
  const таймеры = new Set();
  const интервалы = new Set();
  let погашен = false;

  const окно = {
    name: '',
    location: {
      // Адрес сервера — только наш: «?server=» сильнее запасного 127.0.0.1:8790.
      search: '?server=' + encodeURIComponent(АДРЕС_СЕРВЕРА), protocol: 'http:', host: '127.0.0.1',
      origin: 'http://127.0.0.1', pathname: '/Games/страница.html', hash: '',
      href: 'http://127.0.0.1/Games/страница.html?server=' + encodeURIComponent(АДРЕС_СЕРВЕРА),
      replace: function () {}
    },
    localStorage: null, sessionStorage: null,
    addEventListener: function () {}, removeEventListener: function () {},
    Telegram: { WebApp: { initData: initDataДля(номер), initDataUnsafe: {}, onEvent: function () {}, offEvent: function () {} } },
    ИграПоСети: {
      начать: function () {}, показатьВид: function () { мост.видов++; },
      экран: function () {}, показатьСвязь: function () {}
    },
    btoa: function (с) { return Buffer.from(с, 'binary').toString('base64'); },
    atob: function (с) { return Buffer.from(с, 'base64').toString('binary'); }
  };
  function память() {
    const м = new Map();
    return {
      getItem: function (к) { return м.has(к) ? м.get(к) : null; },
      setItem: function (к, з) { м.set(к, String(з)); },
      removeItem: function (к) { м.delete(к); }
    };
  }
  окно.localStorage = память();
  окно.sessionStorage = память();
  if (играСтраницы !== undefined) окно.ИграСтраницы = играСтраницы;

  const документ = {
    getElementById: function (id) { return страница.узлы.get(id) || null; },
    createElement: function () { return сделатьУзел('', страница); },
    addEventListener: function () {}, removeEventListener: function () {},
    querySelector: function () { return null; }, querySelectorAll: function () { return []; },
    readyState: 'complete', hidden: false, visibilityState: 'visible',
    body: { appendChild: function () {}, removeChild: function () {} }
  };
  const окружение = {
    window: окно, document: документ,
    console: { log: function () {}, warn: function () {}, error: function () {} },
    fetch: function (адрес, настройки) {
      const строка = String(адрес);
      // Песочница не ходит никуда, кроме нашего сервера: 8790 не трогаем.
      if (строка.indexOf(АДРЕС_СЕРВЕРА + '/') !== 0) {
        чужиеАдреса.push(строка);
        return new Promise(function () {});
      }
      const путь = decodeURIComponent(строка.slice(АДРЕС_СЕРВЕРА.length)).split('?')[0];
      let тело = {};
      try { тело = JSON.parse(настройки && настройки.body || '{}'); } catch (с) { тело = {}; }
      запросы.push({ путь: путь, тело: тело });
      if (погашен) return new Promise(function () {});
      return globalThis.fetch(адрес, настройки);
    },
    setTimeout: function (ф, мс) {
      const т = setTimeout(function () { таймеры.delete(т); if (!погашен) ф(); }, мс);
      таймеры.add(т);
      return т;
    },
    clearTimeout: function (т) { таймеры.delete(т); clearTimeout(т); },
    setInterval: function (ф, мс) { const т = setInterval(ф, мс); интервалы.add(т); return т; },
    clearInterval: function (т) { интервалы.delete(т); clearInterval(т); },
    URLSearchParams: URLSearchParams, URL: URL, AbortController: AbortController,
    Promise: Promise, JSON: JSON, Date: Date, Math: Math
  };
  окружение.globalThis = окружение;
  окно.setTimeout = окружение.setTimeout; окно.clearTimeout = окружение.clearTimeout;
  окно.setInterval = окружение.setInterval; окно.clearInterval = окружение.clearInterval;
  окно.fetch = окружение.fetch;
  vm.runInNewContext(ИСХОДНИК_СЕТИ, окружение, { filename: 'js/сеть.js' });

  function погасить() {
    погашен = true;
    таймеры.forEach(function (т) { clearTimeout(т); });
    интервалы.forEach(function (т) { clearInterval(т); });
    таймеры.clear(); интервалы.clear();
  }
  ВСЕ_ГАСИЛКИ.push(погасить);
  return {
    узел: function (id) { return страница.узлы.get(id) || null; },
    видно: function (id) { const у = страница.узлы.get(id); return Boolean(у) && !у.classList.contains('скрыт'); },
    входы: function () { return запросы.filter(function (з) { return з.путь === '/войти'; }); },
    чужиеАдреса: чужиеАдреса, мост: мост, погасить: погасить
  };
}

function подождать(условие, лимитМс) {
  return new Promise(function (готово) {
    const до = Date.now() + (лимитМс || 6000);
    (function шаг() {
      if (условие() || Date.now() > до) return готово();
      setTimeout(шаг, 20);
    })();
  });
}

async function войтиСоСтраницы(играСтраницы, номер, код) {
  const с = поднятьСтраницу(играСтраницы, номер);
  с.узел('поле-кода').value = код;
  с.узел('кнопка-войти').нажать();
  await подождать(function () { return с.узел('сообщение-входа').textContent !== '' || с.мост.видов > 0; });
  return с;
}

async function случайКлиент() {
  console.log('\n5. Страница шлёт свою игру и показывает слова отказа');
  const дурак = await создать(3001);
  const шашки = await создать(3002, 'шашки');

  const сШашек = await войтиСоСтраницы('шашки', 3003, дурак.данные.код);
  const вход1 = сШашек.входы()[0];
  проверить('5) страница шашек шлёт в /войти игру «шашки»', Boolean(вход1) && вход1.тело.игра === 'шашки',
    JSON.stringify(вход1 && вход1.тело));
  const текст1 = сШашек.узел('сообщение-входа').textContent;
  проверить('5) слова: «Это стол игры «Дурак», а сейчас открыт «Шашки». Откройте «Дурак» и введите код там.»',
    текст1 === 'Это стол игры «Дурак», а сейчас открыт «Шашки». Откройте «Дурак» и введите код там.' &&
    сШашек.видно('сообщение-входа'), '«' + текст1 + '»');
  проверить('5) под словами — прежняя кнопка «В лобби»', сШашек.видно('кнопка-отказ-в-лобби'));
  /* Кнопка должна существовать (заводится вместе с «В лобби») и быть
     спрятанной: «нет узла» не считаем за «не показана». */
  проверить('5) «Создать новый стол» при чужом столе не показан (завёл бы стол не той игры)',
    Boolean(сШашек.узел('кнопка-новый-стол')) && !сШашек.видно('кнопка-новый-стол'),
    сШашек.узел('кнопка-новый-стол') ? 'кнопка видна' : 'кнопки нет вовсе');
  проверить('5) за чужой стол не посадили: вида стола мост не получил', сШашек.мост.видов === 0,
    'видов: ' + сШашек.мост.видов);

  const сДурака = await войтиСоСтраницы(undefined, 3004, шашки.данные.код);
  const вход2 = сДурака.входы()[0];
  проверить('5) главная (дурак, без ИграСтраницы) шлёт игру «дурак»', Boolean(вход2) && вход2.тело.игра === 'дурак',
    JSON.stringify(вход2 && вход2.тело));
  const текст2 = сДурака.узел('сообщение-входа').textContent;
  проверить('5) слова: «…стол игры «Шашки», а сейчас открыт «Дурак»…»',
    /^Это стол игры «Шашки», а сейчас открыт «Дурак»\. Откройте «Шашки» и введите код там\.$/.test(текст2), '«' + текст2 + '»');

  const своя = await войтиСоСтраницы('шашки', 3005, шашки.данные.код);
  проверить('5) своя игра: страница шашек садится за стол шашек', своя.мост.видов > 0 &&
    своя.узел('сообщение-входа').textContent === '', 'видов: ' + своя.мост.видов +
    ', слова: «' + своя.узел('сообщение-входа').textContent + '»');

  const чужие = [сШашек, сДурака, своя].reduce(function (в, с) { return в.concat(с.чужиеАдреса); }, []);
  проверить('5) песочница не стучалась ни на какой адрес, кроме тестового сервера', чужие.length === 0, чужие.join(', '));
}

