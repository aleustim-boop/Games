async function главное() {
  setTimeout(function () {
    console.log('  ПРОВАЛ проверка не уложилась в 120 с — что-то повисло');
    process.exit(1);
  }, 120000).unref();

  загрузитьКод();
  сервера.оснасткаДляПроверки(ТОКЕН, function () { return { ok: true, result: {} }; });
  const сервер = сервера.создатьСервер();
  try {
    await new Promise(function (готово, беда) {
      сервер.once('error', беда);
      сервер.listen(ПОРТ, '127.0.0.1', готово);
    });
  } catch (сбой) {
    console.log('  ПРОВАЛ порт ' + ПОРТ + ' занят — с чужой копией не разговариваем: ' + сбой.message);
    console.log('\nИтого проверок: 1, провалов: 1');
    process.exit(1);
  }
  console.log('Тестовый сервер поднят в этом процессе на порту ' + ПОРТ + ', PID ' + process.pid + ' (8790 не трогаем)');

  try {
    await случайСервер();
    await случайЗахватОткрыт();
    await случайИгрыНет();
    await случайКлиент();
    await случайМусор();
  } catch (сбой) {
    провалов++;
    console.log('  ПРОВАЛ проверка упала: ' + (сбой && сбой.stack || сбой));
  } finally {
    ВСЕ_ГАСИЛКИ.forEach(function (погасить) { погасить(); });
    if (typeof сервер.closeAllConnections === 'function') сервер.closeAllConnections();
    await new Promise(function (готово) { сервер.close(готово); });
    сервера.оснасткаДляПроверки();
    try { fs.rmSync(process.env.ДАННЫЕ_ИГРЫ, { recursive: true, force: true }); } catch (е) { /* не страшно */ }
    if (ЛОМАЕМ) { try { fs.rmSync(КОРЕНЬ_КОДА, { recursive: true, force: true }); } catch (е) { /* не страшно */ } }
  }

  if (всего < 25) {
    провалов++;
    console.log('  ПРОВАЛ выполнено подозрительно мало проверок: ' + всего);
  }
  console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
  /* Не process.exit(): на Windows он рвёт ещё закрывающиеся соединения
     fetch из песочницы и падает внутри libuv с кодом 127. Ставим код
     выхода и даём процессу закончиться самому. */
  process.exitCode = провалов > 0 ? 1 : 0;
}

