// Сдача, отказ черновика, выбывание, «я» только потерял область, перевод между боями (боты так не делают).
function проверкаСдачиИПереводов(Р) {
  const сдача = { вид: 'сдался', кто: 'Маша', областей: 2 };
  const отказ = { вид: 'черновик не принят', кто: 'Коля', причина: 'Из Брода можно отправить не больше 6' };
  const выбыл = { вид: 'выбыл', кто: 'Маша', раунд: 3, областейНаНачалоРаунда: 2 };
  const удар = событиеУдара(11, { кто: 'Петя', у: 'Коля', исход: 'взята', сколько: 4, защитников: 2, осталось: 3 });
  const входа = (события, я) => ({ события: события, раунд: 3, карта: 'материк', имена: {}, я: я });
  const р = Р.построить(входа([сдача, отказ, удар, выбыл], 'Маша'));
  проверить(р.журнал[0] === 'Сдача: Маша — области стали ничьими', 'сдача: строка сдачи (вышло «' + р.журнал[0] + '»)');
  проверить(р.журнал[1] === 'Приказы Коли не приняты: Из Брода можно отправить не больше 6', 'сдача: строка отказа (вышло «' + р.журнал[1] + '»)');
  проверить(р.журнал.length === 3, 'сдача: в журнале ' + р.журнал.length + ' строки, ждали 3 (выбывший строки не даёт)');
  const ж = шагиВида(р, 'журнал');
  проверить(ж.length === 3 && ж[0].с === 0 && ж[1].с === 0 && ж[2].с === 2000,
    'сдача: время журнала сдачи и отказа 0 мс, первого боя 2000 (вышло ' + ж.map((ш) => ш.с).join() + ')');
  проверить(р.итог[0] === 'Вы сдались', 'сдача: «я» сдался — первая строка «Вы сдались» (вышло «' + р.итог[0] + '»)');
  проверить(р.итог[1] === 'Выбывает из игры: Маша', 'сдача: главное — выбывает Маша (вышло «' + р.итог[1] + '»)');
  // Тот, кого только ударили (был «у»): первая строка про него.
  const потерял = Р.построить(входа([удар], 'Коля'));
  проверить(потерял.итог[0] === 'Вы: ' + МИНУС + '1 · потеряно 2 войска', 'сдача: «я» только потерял область (вышло «' + потерял.итог[0] + '»)');
  // Тот, кто только выбыл.
  const тольковыбыл = Р.построить(входа([выбыл], 'Маша'));
  проверить(тольковыбыл.итог[0] === 'Вы: без захватов', 'сдача: «я» только выбыл — строка про него (вышло «' + тольковыбыл.итог[0] + '»)');
  // Посторонний — общая строка.
  const чужой = Р.построить(входа([удар], 'Гена'));
  проверить(чужой.итог[0] === 'Взято областей: 1', 'сдача: посторонний видит общую строку (вышло «' + чужой.итог[0] + '»)');

  // Перевод между двумя встречными боями: порядок шагов «журнал» = порядок массива.
  const встречный = (а, б) => ({
    вид: 'встречный', области: [а, б], исход: 'прошла', прошла: 'Петя', обмены: [],
    колонны: [{ кто: 'Петя', откуда: а, куда: б, было: 5, осталось: 3 }, { кто: 'Маша', откуда: б, куда: а, было: 4, осталось: 0 }]
  });
  const перевод = { вид: 'перевод', кто: 'Коля', откуда: 16, куда: 15, сколько: 2 };
  const смесь = Р.построить(входа([встречный(10, 11), встречный(12, 13), перевод, удар], null));
  const жс = шагиВида(смесь, 'журнал');
  проверить(JSON.stringify(жс.map((ш) => ш.текст)) === JSON.stringify(смесь.журнал),
    'перевод: шаги «журнал» идут не как массив журнал (' + жс.map((ш) => ш.с).join() + ')');
  проверить(жс.every((ш, и) => и === 0 || ш.с >= жс[и - 1].с), 'перевод: время журнала убывает (' + жс.map((ш) => ш.с).join() + ')');
  проверить(жс[2].текст.indexOf('Перевод Коли') === 0 && жс[2].с === 2600,
    'перевод: стоит со временем второго боя 2600 (вышло ' + жс[2].текст + ' @' + жс[2].с + ')');
}

// «Край взят» и порядок важности итога: столица > выбыл > край > встречный > захват.
function проверкаКраяИВажности(Р) {
  // Остров, край «Кряж» = области 1–4. До: три у Пети, четвёртая у Маши. После: все четыре у Пети.
  const до = Array(19).fill(null);
  [1, 2, 3].forEach((н) => { до[н] = 'Петя'; });
  до[4] = 'Маша';
  const после = до.slice();
  после[4] = 'Петя';
  const захват = { вид: 'удар', кто: 'Петя', откуда: [{ область: 3, сколько: 5 }], куда: 4, сколько: 5, у: 'Маша', защитников: 1,
    выстрелыНападающих: [], выстрелыЗащитников: [], выбитоЗащитников: 1, выбитоНападающих: 0,
    исход: 'взята', осталось: 5, домой: 0, столица: false };
  const встр = { вид: 'встречный', области: [5, 6], исход: 'прошла', прошла: 'Коля', обмены: [],
    колонны: [{ кто: 'Коля', откуда: 5, куда: 6, было: 3, осталось: 2 }, { кто: 'Боря', откуда: 6, куда: 5, было: 2, осталось: 0 }] };
  const вып = { вид: 'выбыл', кто: 'Маша', раунд: 2, областейНаНачалоРаунда: 1 };
  const стол = Object.assign({}, захват, { куда: 7, столица: true, у: 'Боря' });
  const собрать = (события, добавка) => Р.построить(Object.assign({ события: события, раунд: 2, карта: 'остров', имена: {}, хозяеваДо: до, хозяеваПосле: после }, добавка));

  // Край целиком перешёл к Пете.
  const край = собрать([захват]);
  проверить(край.итог[1] === 'Край «Кряж» взят: Петя', 'край: главная строка (вышло «' + край.итог[1] + '»)');
  проверить(край.итог[2] === 'Петя взял Утёс у Маши', 'край: третья строка — обычный захват (вышло «' + край.итог[2] + '»)');
  // Край уже был у Пети до раунда — «взят» не пишем.
  const былРанее = собрать([захват], { хозяеваДо: после });
  проверить(былРанее.итог.every((с) => с.indexOf('Край') === -1), 'край: край, что и так был у Пети, назван взятым');
  // Не весь край — не пишем.
  const частично = после.slice();
  частично[2] = 'Коля';
  const неВесь = собрать([захват], { хозяеваПосле: частично });
  проверить(неВесь.итог.every((с) => с.indexOf('Край') === -1), 'край: неполный край назван взятым');
  // Без хозяев до и после края не определить — и не падаем.
  const безХозяев = собрать([захват], { хозяеваДо: undefined, хозяеваПосле: undefined });
  проверить(безХозяев.итог.every((с) => с.indexOf('Край') === -1), 'край: без массивов хозяев строки про край быть не должно');

  // Порядок важности: снимаем самое важное по одному — главная строка (итог[1]) переходит ниже.
  const все = [встр, захват, вып, стол];
  // Край определяется по массивам хозяев, не по событиям: «без края» — хозяева до и после одинаковые.
  const безКрая = { хозяеваПосле: до };
  const главная = (события, добавка) => собрать(события, добавка).итог[1];
  проверить(главная(все).indexOf('Столица взята') === 0, 'важность: первой столица (вышло «' + главная(все) + '»)');
  проверить(главная([встр, захват, вып]) === 'Выбывает из игры: Маша', 'важность: без столицы — выбыл (вышло «' + главная([встр, захват, вып]) + '»)');
  проверить(главная([встр, захват]).indexOf('Край') === 0, 'важность: без выбывшего — край (вышло «' + главная([встр, захват]) + '»)');
  проверить(главная([встр, захват], безКрая) === 'Встречный бой Маяк ↔ Фьорд',
    'важность: без края — встречный бой (вышло «' + главная([встр, захват], безКрая) + '»)');
  проверить(главная([захват], безКрая) === 'Петя взял Утёс у Маши', 'важность: один захват — обычный захват (вышло «' + главная([захват], безКрая) + '»)');
}

// Настоящие раунды: боты играют партии, расписание строится по каждому разбору.
function проверкаНастоящихРаундов(Р, Правила, Бот) {
  const всеИмена = ['Аня', 'Боря', 'Вика', 'Гена', 'Дина', 'Егор'];
  let раундов = 0;
  let спеРекраской = 0;
  let сКаплями = 0;
  let сострокой = 0;
  let сПачкой = 0;
  const плохие = [];
  const поКартам = { остров: 0, материк: 0 };
  const поМестам = {};
  // Все числа мест: 2–3 — остров, 4–6 — материк (ТЗ 2.2). Зерно у каждой пары «места, зерно» своё.
  const запуски = [];
  [2, 3, 4, 5, 6].forEach((мест) => { for (let з = 1; з <= 8; з++) запуски.push({ мест: мест, зерно: мест * 100 + з }); });
  for (const запуск of запуски) {
    const зерно = запуск.зерно;
    const имена = {};
    всеИмена.slice(0, запуск.мест).forEach((и) => { имена[и] = и; });
    const случай = генератор(зерно);
    let партия = Правила.новаяПартия({ игроки: Object.keys(имена) }, случай);
    const ждёмКарту = запуск.мест <= 3 ? 'остров' : 'материк';
    проверить(партия.карта === ждёмКарту, 'настоящие раунды: на ' + запуск.мест + ' места карта ' + партия.карта + ', ждали ' + ждёмКарту);
    const уровни = ['лёгкий', 'обычный', 'сложный'];
    while (!партия.завершена && раундов < 100000) {
      const черновики = {};
      партия.игроки.forEach((к, и) => {
        if (партия.выбыли[к]) return;
        черновики[к] = Бот.решить(партия, к, уровни[(зерно + и) % 3], случай);
      });
      const р = Правила.разобратьРаунд(партия, черновики, случай);
      const расписание = Р.построить({
        события: р.события, раунд: р.раунд, карта: партия.карта, имена: имена, я: 'Аня',
        хозяеваДо: партия.хозяева, хозяеваПосле: р.партия.хозяева
      });
      раундов++;
      поКартам[партия.карта]++;
      поМестам[запуск.мест] = (поМестам[запуск.мест] || 0) + 1;
      const шаги = расписание.шаги;
      // Порядок шагов «журнал» — как в массиве журнал, время не убывает.
      const журналШаги = шагиВида(расписание, 'журнал');
      if (JSON.stringify(журналШаги.map((ш) => ш.текст)) !== JSON.stringify(расписание.журнал)) {
        плохие.push('зерно ' + зерно + ': шаги «журнал» идут не как массив журнал');
      }
      if (расписание.всегоМс !== 8000 || !шаги.length) плохие.push('зерно ' + зерно + ': всего ' + расписание.всегоМс);
      if (!шаги.every((ш) => ш.с >= 0 && ш.с + ш.длит <= 8000 && Number.isFinite(ш.с))) плохие.push('зерно ' + зерно + ': шаг вне 0–8000');
      шаги.forEach((ш) => {
        if (ш.вид !== 'перекраска') return;
        const раньше = шаги.some((в) => в.вид === 'вспышка' && в.области.indexOf(ш.область) !== -1 && в.с < ш.с);
        if (!раньше) плохие.push('зерно ' + зерно + ': перекраска области ' + ш.область + ' без вспышки раньше');
      });
      шаги.forEach((ш) => {
        if (ш.вид !== 'вспышка') return;
        const раньше = шаги.some((в) => в.вид === 'капли' && в.с < ш.с);
        if (!раньше) плохие.push('зерно ' + зерно + ': вспышка без капель раньше');
      });
      const тексты = расписание.журнал.concat(расписание.итог);
      if (тексты.some((т) => /undefined|NaN|null|\[object/.test(т))) плохие.push('зерно ' + зерно + ': мусор в строках ' + JSON.stringify(тексты));
      if (расписание.итог.length < 2 || расписание.итог.length > 3) плохие.push('зерно ' + зерно + ': в итоге ' + расписание.итог.length + ' строк');
      const строкЖурналаЖдём = р.события.filter((с) => ['встречный', 'удар', 'рассеялись', 'перевод', 'сдался', 'черновик не принят'].indexOf(с.вид) !== -1).length;
      if (расписание.журнал.length !== строкЖурналаЖдём) плохие.push('зерно ' + зерно + ': строк журнала ' + расписание.журнал.length + ', событий ' + строкЖурналаЖдём);
      if (шагиВида(расписание, 'перекраска').length) спеРекраской++;
      if (шагиВида(расписание, 'капли').length) сКаплями++;
      if (расписание.журнал.length) сострокой++;
      if (расписание.боёвВПачке > 1) сПачкой++;
      партия = р.партия;
    }
  }
  проверить(плохие.length === 0, 'настоящие раунды: ' + плохие.slice(0, 3).join(' | ') + (плохие.length > 3 ? ' … всего ' + плохие.length : ''));
  проверить(раундов >= 100, 'настоящие раунды: сыграно всего ' + раундов + ', ждали не меньше 100');
  проверить(спеРекраской > 0, 'настоящие раунды: ни одной перекраски (ноль найденного — провал)');
  проверить(сКаплями > 0, 'настоящие раунды: ни одного боя (ноль найденного — провал)');
  проверить(сострокой > 0, 'настоящие раунды: ни одной строки журнала (ноль найденного — провал)');
  проверить(поКартам.остров >= 20 && поКартам.материк >= 20, 'настоящие раунды: по картам ' + JSON.stringify(поКартам) + ', ждали ≥20 на каждой');
  проверить([2, 3, 4, 5, 6].every((м) => (поМестам[м] || 0) >= 10), 'настоящие раунды: по числу мест ' + JSON.stringify(поМестам) + ', ждали ≥10 на каждом');
  console.log('  настоящих раундов: ' + раундов + ' (по картам ' + JSON.stringify(поКартам) + ', по местам ' + JSON.stringify(поМестам) +
    '), с перекраской: ' + спеРекраской + ', с пачками боёв: ' + сПачкой);
}

