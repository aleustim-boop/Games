// Случай по зерну (Mulberry32): проверка повторяема.
function генератор(зерно) {
  let с = зерно >>> 0;
  return function () {
    с = (с + 0x6D2B79F5) >>> 0;
    let т = с;
    т = Math.imul(т ^ (т >>> 15), т | 1);
    т ^= т + Math.imul(т ^ (т >>> 7), т | 61);
    return ((т ^ (т >>> 14)) >>> 0) / 4294967296;
  };
}

function случайОчередь(числа) {
  let и = 0;
  return function () {
    if (и >= числа.length) throw new Error('очередь случая кончилась');
    return числа[и++];
  };
}

function шагиВида(р, вид) {
  return р.шаги.filter((ш) => ш.вид === вид);
}

function меньшееС(р, вид) {
  const с = шагиВида(р, вид).map((ш) => ш.с);
  return с.length ? Math.min(...с) : null;
}

