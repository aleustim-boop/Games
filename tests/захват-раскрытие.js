// Пример раунда из ТЗ 14 — как в tests/захват-правила.js (те же числа случая).
function примерРаунда14(Правила) {
  const п = Правила.новаяПартия({
    игроки: ['Петя', 'Маша', 'Коля'],
    столицы: { Петя: 'B', Маша: 'G', Коля: 'O' },
    порядок: ['Петя', 'Маша', 'Коля'],
    областейНаСтарте: 2,
    карта: 'материк'
  }, () => 0);
  for (let н = 1; н < п.хозяева.length; н++) п.хозяева[н] = null;
  п.хозяева[10] = 'Петя'; п.хозяева[11] = 'Маша'; п.хозяева[16] = 'Коля';
  п.войска[10] = 6; п.войска[11] = 3; п.войска[16] = 4;
  п.раунд = 4;
  п.подкрепление = { Петя: 5, Маша: 4, Коля: 3 };
  const черновики = {
    Петя: { расстановка: { 10: 5 }, приказы: [{ из: 10, в: 11, сколько: 10 }] },
    Маша: { расстановка: { 11: 4 }, приказы: [{ из: 11, в: 10, сколько: 6 }] },
    Коля: { расстановка: { 16: 3 }, приказы: [{ из: 16, в: 11, сколько: 6 }] }
  };
  const П1 = 0.1; // попал
  const М = 0.9; // промах
  const ряд = (попал, мимо) => Array(попал).fill(П1).concat(Array(мимо).fill(М));
  const числа = [].concat(ряд(5, 5), ряд(4, 2), ряд(1, 5), ряд(1, 0), ряд(1, 5), ряд(1, 0), ряд(3, 2), ряд(4, 1));
  const р = Правила.разобратьРаунд(п, черновики, случайОчередь(числа));
  return { до: п, разбор: р };
}

