// «Край взят» и порядок важности итога: столица > выбыл > край > встречный > захват.
function проверкаКраяИВажности(Р) {
  // Остров, край «Кряж» = области 1–4. До: три у Пети, четвёртая у Маши. После: все четыре у Пети.
  const до = Array(19).fill(null);
  [1, 2, 3].forEach((н) => { до[н] = 'Петя'; });
  до[4] = 'Маша';
  const после = до.slice();
  после[4] = 'Петя';
  const захват = { вид: 'удар', кто: 'Петя', откуда: [{ область: 3, сколько: 5 }], куда: 4, сколько: 5, у: 'Маша', защитников: 1,
    выстрелыНападающих: [], выстрелыЗащитников: [], выбитоЗащитников: 1, выбитоНападающих: 0,
    исход: 'взята', осталось: 5, домой: 0, столица: false };
  const встр = { вид: 'встречный', области: [5, 6], исход: 'прошла', прошла: 'Коля', обмены: [],
    колонны: [{ кто: 'Коля', откуда: 5, куда: 6, было: 3, осталось: 2 }, { кто: 'Боря', откуда: 6, куда: 5, было: 2, осталось: 0 }] };
  const вып = { вид: 'выбыл', кто: 'Маша', раунд: 2, областейНаНачалоРаунда: 1 };
  const стол = Object.assign({}, захват, { куда: 7, столица: true, у: 'Боря' });
  const собрать = (события, добавка) => Р.построить(Object.assign({ события: события, раунд: 2, карта: 'остров', имена: {}, хозяеваДо: до, хозяеваПосле: после }, добавка));

  // Край целиком перешёл к Пете.
  const край = собрать([захват]);
  проверить(край.итог[1] === 'Край «Кряж» теперь у Пети', 'край: главная строка (вышло «' + край.итог[1] + '»)');
  проверить(край.итог[2] === 'Утёс теперь у Пети: 5 против 1', 'край: третья строка — обычный захват (вышло «' + край.итог[2] + '»)');
  // Край уже был у Пети до раунда — «взят» не пишем.
  const былРанее = собрать([захват], { хозяеваДо: после });
  проверить(былРанее.итог.every((с) => с.indexOf('Край') === -1), 'край: край, что и так был у Пети, назван взятым');
  // Не весь край — не пишем.
  const частично = после.slice();
  частично[2] = 'Коля';
  const неВесь = собрать([захват], { хозяеваПосле: частично });
  проверить(неВесь.итог.every((с) => с.indexOf('Край') === -1), 'край: неполный край назван взятым');
  // Без хозяев до и после края не определить — и не падаем.
  const безХозяев = собрать([захват], { хозяеваДо: undefined, хозяеваПосле: undefined });
  проверить(безХозяев.итог.every((с) => с.indexOf('Край') === -1), 'край: без массивов хозяев строки про край быть не должно');

  // Порядок важности: снимаем самое важное по одному — главная строка (итог[1]) переходит ниже.
  const все = [встр, захват, вып, стол];
  // Край определяется по массивам хозяев, не по событиям: «без края» — хозяева до и после одинаковые.
  const безКрая = { хозяеваПосле: до };
  const главная = (события, добавка) => собрать(события, добавка).итог[1];
  проверить(главная(все).indexOf('Столица Башня теперь') === 0, 'важность: первой столица (вышло «' + главная(все) + '»)');
  проверить(главная([встр, захват, вып]) === 'Выбывает из игры: Маша', 'важность: без столицы — выбыл (вышло «' + главная([встр, захват, вып]) + '»)');
  проверить(главная([встр, захват]).indexOf('Край') === 0, 'важность: без выбывшего — край (вышло «' + главная([встр, захват]) + '»)');
  проверить(главная([встр, захват], безКрая) === 'Встречный бой: Коля ' + МИНУС + '1, Боря ' + МИНУС + '2',
    'важность: без края — встречный бой (вышло «' + главная([встр, захват], безКрая) + '»)');
  проверить(главная([захват], безКрая) === 'Утёс теперь у Пети: 5 против 1', 'важность: один захват — обычный захват (вышло «' + главная([захват], безКрая) + '»)');
}

