  проверить(потерял.итог[2] === 'Пришли 4 против ваших 2' && потерял.итог.indexOf('Край «Кряж» потерян: −2 войска в раунд') === -1,
    'Д-10а: потерял Утёс — третьей строкой ждали причину «Пришли 4 против ваших 2» (вышло ' + потерял.итог.join(' | ') + ')');
