  проверить(всеЧетыре.журнал.concat(всеЧетыре.итог).every((с) => с.indexOf('потерян') === -1),
    'Д-10а: бот взял весь Кряж — лишняя строка «потерян» (вышло ' + всеЧетыре.итог.join(' | ') + ')');
  проверить(всеЧетыре.стрелкиИтога.length === 3, 'Д-10а: четыре удара по вам — стрелок не больше трёх (вышло ' + всеЧетыре.стрелкиИтога.length + ')');

  // (г) Отбитый удар: «Площадь устояла», «Брод устоял», «Ущелье устояло»; старого «удар отбит —» в пластине нет.
