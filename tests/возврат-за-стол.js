/** Поднять копию сервера из указанного корня на указанном порту. */
function поднятьСервер(корень, порт) {
  // Каждый require по своему абсолютному пути — своя копия модуля
  // и своя память комнат: настоящий сервер (8790) этот процесс не трогает.
  const сервера = require(path.join(корень, 'server', 'сервер.js'));
  const комнаты = require(path.join(корень, 'server', 'комнаты.js'));
  const http = сервера.создатьСервер();
  return new Promise(function (готово, беда) {
    http.once('error', беда);
    http.listen(порт, '127.0.0.1', function () { готово({ http: http, сервера: сервера, комнаты: комнаты }); });
  });
}

function погасить(http) {
  return new Promise(function (готово) { http.close(function () { готово(); }); });
}

/* -----------------------------------------------------------------------
   Поддельный игрок: те же запросы, что шлёт браузер
   ----------------------------------------------------------------------- */

function создатьИгрока(адрес, имя) {
  return {
    имя: имя,
    код: null,
    пропуск: null,
    вид: null,
    последнийОтвет: null,

    async запрос(путь, тело) {
      const ответ = await fetch(адрес + путь, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(тело || {})
      });
      const текст = await ответ.text();
      return { статус: ответ.status, тело: текст ? JSON.parse(текст) : null };
    },

    /** доп — необязательные настройки стола (например, { мест: 2 }): любая
     *  понятая настройка включает комнате прихожую с кнопкой «Начать»
     *  (см. применитьНастройки/создатьКомнату в server/комнаты.js) — без
     *  этого список «застолом» в ответе сервер вообще не присылает. */
    async создать(доп) {
      const ответ = await this.запрос('/создать', Object.assign({ имя: this.имя }, доп || {}));
      this.последнийОтвет = ответ;
      if (ответ.тело && ответ.тело.пропуск) {
        this.код = ответ.тело.код;
        this.пропуск = ответ.тело.пропуск;
        this.вид = ответ.тело.состояние || null;
      }
      return ответ;
    },

    async войти(код) {
      const ответ = await this.запрос('/войти', { код: код, имя: this.имя });
      this.последнийОтвет = ответ;
      if (ответ.тело && ответ.тело.пропуск) {
        this.код = ответ.тело.код;
        this.пропуск = ответ.тело.пропуск;
        this.вид = ответ.тело.состояние || null;
      }
      return ответ;
    },

    async состояние() {
      const ответ = await this.запрос('/состояние', { код: this.код, пропуск: this.пропуск });
      this.последнийОтвет = ответ;
      if (ответ.статус === 200 && ответ.тело && ответ.тело.состояние) this.вид = ответ.тело.состояние;
      return ответ;
    },

    /** Добровольный уход — тот же путь, что кнопка «Выйти» на экране игры. */
    async выйти() {
      const ответ = await this.запрос('/выйти', { код: this.код, пропуск: this.пропуск });
      this.последнийОтвет = ответ;
      return ответ;
    },

    /** Действие комнаты («начать», «ещё», …) — та же дверь /ход, что кнопки на экране игры. */
    async ход(действие, доп) {
      const ответ = await this.запрос('/ход',
        Object.assign({ код: this.код, пропуск: this.пропуск, действие: действие }, доп || {}));
      this.последнийОтвет = ответ;
      if (ответ.тело && ответ.тело.состояние) this.вид = ответ.тело.состояние;
      return ответ;
    }
  };
}

/* -----------------------------------------------------------------------
   Главный сценарий: двое за столом, партия идёт, первый пропадает молча
   ----------------------------------------------------------------------- */

/**
 * Свести двоих за настоящий стол на двоих (не «компания» — обычная игра
 * с другом по коду). Комната на двоих без хозяина-компании раздаёт карты
 * сама, как только второй занял последнее место — кнопки «Начать» тут нет.
 */
async function свестиДвоих(адрес) {
  const первый = создатьИгрока(адрес, 'Первый');
  const второй = создатьИгрока(адрес, 'Второй');
  await первый.создать();
  await второй.войти(первый.код);
  await первый.состояние();   // подтянуть вид уже после того, как партия стартовала
  return { первый: первый, второй: второй };
}

/**
 * То же самое, но стол-КОМПАНИЯ на два места, а не обычная игра «на двоих
 * по коду». Разница важна ровно для одной вещи: список мест («застолом»)
 * сервер кладёт в ответ, ТОЛЬКО когда комната.компания === true (см.
 * показатьИгроку в server/комнаты.js: «Комната на двоих этого списка не
 * передаёт вовсе»). А поле «неДождался» из П.2 живёт ровно в этом списке —
 * значит, проверить его в обычной игре «на двоих по коду» физически
 * нельзя, и для этого нужен именно стол-компания.
 *
 * Настройка «мест: 2» — самая безобидная понятая настройка (число мест
 * не меняется, оно и так 2 по умолчанию для дурака), но она включает
 * прихожую (см. применитьНастройки), и поэтому раздача не стартует сама:
 * хозяин должен явно нажать «Начать» — это и делает первый.ход('начать').
 */
async function свестиДвоихКомпанией(адрес) {
  const первый = создатьИгрока(адрес, 'Первый');
  const второй = создатьИгрока(адрес, 'Второй');
  await первый.создать({ мест: 2 });
  await второй.войти(первый.код);
  await первый.ход('начать');
  await первый.состояние();
  await второй.состояние();
  return { первый: первый, второй: второй };
}

/**
 * Своё место или место соперника из списка «застолом» — по признаку
 * «этоЯ». Списка нет вовсе (обычная игра «на двоих по коду», не компания)
 * или места с таким признаком нет — возвращаем undefined честно, а не
 * пустой объект: вызывающий код это тут же и проверит («ноль найденного —
 * провал», а не тихий пропуск).
 */
function местоВЗастолом(вид, этоЯ) {
  const список = вид && Array.isArray(вид.застолом) ? вид.застолом : null;
  if (!список) return undefined;
  return список.find(function (м) { return м.этоЯ === этоЯ; });
}

/* -----------------------------------------------------------------------
   Лимит времени на ход (план «время на ход»): стол на ТРОИХ и «болван»,
   который двигает очередь до нужного места.
   ----------------------------------------------------------------------- */

/**
 * Стол-компания на ТРИ места, трое живых людей (не бот): партия.игроки.length
 * (3) больше минимума мест дурака (2) — это и нужно, чтобы пропажа одного
 * НЕ закрывала партию (см. «выйти» в server/комнаты.js: «если игроков больше
 * минимума — место превращается в бота, слово 'пропал-бот', иначе партия
 * закрывается без победителя словом 'пропал'»). Трое живых людей проще
 * бота-наполнителя: ботом рулит свой насос с задержкой (темпБота), а тут
 * каждым ходом распоряжается сам сценарий — предсказуемо и без гонок.
 *
 * лимитСекундНаХод ставим ДО раздачи, тем же способом, что и «мест»
 * (применитьНастройки бесхитростно берёт число как есть, см. её комментарий
 * в server/комнаты.js) — раздатьПартию потом читает комната.лимитСекундНаХод.
 */
async function свестиТроихКомпанией(адрес, лимитСекундНаХод) {
  const первый = создатьИгрока(адрес, 'Первый');
  const второй = создатьИгрока(адрес, 'Второй');
  const третий = создатьИгрока(адрес, 'Третий');
  await первый.создать({ мест: 3, лимитСекундНаХод: лимитСекундНаХод });
  await второй.войти(первый.код);
  await третий.войти(первый.код);
  await первый.ход('начать');
  await первый.состояние();
  await второй.состояние();
  await третий.состояние();
  return { первый: первый, второй: второй, третий: третий };
}

/** Номер места, чья сейчас очередь («ходит») — по общему списку «застолом». */
function ходящееМесто(вид) {
  const список = вид && Array.isArray(вид.застолом) ? вид.застолом : null;
  if (!список) return undefined;
  const место = список.find(function (м) { return м.ходит === true; });
  return место ? место.номер : undefined;
}

/** Свой номер места из вида — то же «местоВЗастолом», но короче для частого случая. */
function свойНомер(вид) {
  const своё = местоВЗастолом(вид, true);
  return своё ? своё.номер : undefined;
}

/**
 * Один ход «болвана»: не думает о стратегии, просто перебирает свою руку,
 * пока сервер не примет какую-нибудь карту (тот же приём, что и в
 * tests/сетевой-автопрогон.js). Нужен только затем, чтобы сдвинуть очередь
 * хода на нужное место, — какими картами это делается, для сценария
 * не важно.
 */
async function болванСходить(игрок) {
  const вид = игрок.вид;
  if (!вид) {
    throw new Error('у ' + игрок.имя + ' нет вида партии, сходить нечем');
  }
  if (вид.фаза === 'защита') {
    const беру = await игрок.ход('беру');
    if (!беру.тело || !беру.тело.принято) {
      throw new Error(игрок.имя + ' не смог сказать «Беру»: ' + JSON.stringify(беру.тело));
    }
    return;
  }
  const рука = Array.isArray(вид.мояРука) ? вид.мояРука : [];
  for (let карта = 0; карта < рука.length; карта++) {
    const ответ = await игрок.ход('ходить', { карта: карта });
    if (ответ.тело && ответ.тело.принято) return;
  }
  const бито = await игрок.ход('бито');
  if (бито.тело && бито.тело.принято) return;
  throw new Error(игрок.имя + ' не смог сходить ни одной картой из руки, и «Бито» тоже не приняли: ' +
    JSON.stringify(бито.тело) + ' (фаза ' + вид.фаза + ', карт в руке ' + рука.length + ')');
}

/**
 * Довести партию до состояния «сейчас ходит именно цель» — играя за всех
 * остальных «болваном» по кругу. Кто окажется атакующим сразу после раздачи,
 * решает случайная раздача карт (младший козырь) — поэтому шагов может
 * понадобиться от нуля до пары: цикл, а не жёсткое «первый сходил один раз».
 * Не дошли за разумное число попыток — честный провал с объяснением, а не
 * зависшая проверка («ноль найденного — провал»).
 */
async function довестиОчередьДо(картаМест, цель, префикс, макс) {
  const предел = макс || 6;
  for (let попытка = 0; попытка < предел; попытка++) {
    await цель.состояние();
    const номерХодящего = ходящееМесто(цель.вид);
    const свойНомерЦели = свойНомер(цель.вид);
    if (номерХодящего === свойНомерЦели) return true;
    if (номерХодящего === undefined || !картаМест[номерХодящего]) {
      проверить(префикс + ': видно, чья сейчас очередь (список «застолом» отдаёт место с «ходит»)',
        false, 'вид цели (' + цель.имя + '): ' + JSON.stringify(цель.вид && цель.вид.застолом));
      return false;
    }
    const текущий = картаМест[номерХодящего];
    await текущий.состояние();
    try {
      await болванСходить(текущий);
    } catch (е) {
      проверить(префикс + ': очередь удалось довести до нужного места («болван» сходил за остальных)',
        false, 'сходить за ' + текущий.имя + ' не удалось: ' + е.message);
      return false;
    }
  }
  проверить(префикс + ': очередь дошла до нужного места за разумное число ходов',
    false, 'за ' + предел + ' попыток очередь так и не дошла до ' + цель.имя +
      ' (место ' + свойНомер(цель.вид) + '), ходящее место сейчас: ' + ходящееМесто(цель.вид));
  return false;
}

/**
 * Сценарий «лимит времени: принудительный ход перебивает «пропал-бот»».
 *
 * Стол на троих, лимитСекундНаХод включён маленьким числом секунд. Первый
 * пропадает молча (как при перезагрузке телефона) — за столом трое, поэтому
 * партия НЕ закрывается, его место становится ботом, и второй с третьим
 * видят слово 'пропал-бот' (не 'пропал' — тот только для стола вдвоём).
 * Дальше сценарий доводит очередь ровно до второго и ждёт НАСТОЯЩЕЕ время
 * (реальный setTimeout сервера, не эмуляция!) больше лимита хода — слово
 * события обязано смениться на 'ход-по-времени': старое 'пропал-бот' не
 * должно висеть до следующего настоящего события (это и было замечанием
 * ревьюера 22.09, см. докблок над «сработалаПросрочка» в server/комнаты.js).
 *
 * партииМодуль — server/партия-по-сети.js той же временной копии, откуда
 * поднят сервер: (г) проверяет словарь слов НАПРЯМУЮ, без похода через
 * сервер, — так отдельно видно, готов ли словарь, даже если событие ещё
 * не долетело до игрока по какой-то другой причине.
 */
async function сценарийЛимитВремени(адрес, комнаты, партииМодуль, префикс) {
  const ЛИМИТ_СЕКУНД = 2;
  const { первый, второй, третий } = await свестиТроихКомпанией(адрес, ЛИМИТ_СЕКУНД);

  проверить(префикс + ': партия на троих стартовала (этап «игра»)',
    Boolean(первый.вид) && первый.вид.этап === 'игра',
    'этап после начала: ' + JSON.stringify(первый.вид && первый.вид.этап));
  if (!первый.вид || первый.вид.этап !== 'игра') return;

  const кодКомнаты = первый.код;
  const местоПервого = местоВЗастолом(первый.вид, true);
  const местоВторого = местоВЗастолом(второй.вид, true);
  const местоТретьего = местоВЗастолом(третий.вид, true);
  проверить(префикс + ': у всех троих в списке «застолом» нашлось своё место',
    Boolean(местоПервого) && Boolean(местоВторого) && Boolean(местоТретьего),
    'первый: ' + JSON.stringify(местоПервого) + ', второй: ' + JSON.stringify(местоВторого) +
      ', третий: ' + JSON.stringify(местоТретьего));
  if (!местоПервого || !местоВторого || !местоТретьего) return;

  const картаМест = {};
  картаМест[местоПервого.номер] = первый;
  картаМест[местоВторого.номер] = второй;
  картаМест[местоТретьего.номер] = третий;

  const довели = await довестиОчередьДо(картаМест, второй, префикс);
  if (!довели) return;

  // Второй и третий держат открытый долгий опрос — тот же приём, что
  // и в сценарийДолгогоОбрыва: иначе скачок времени состарит молчание
  // всех троих одинаково, и «пропавшим» мог бы оказаться не тот.
  await второй.состояние();
  await третий.состояние();
  const версияВторого = второй.вид && второй.вид.версия;
  const версияТретьего = третий.вид && третий.вид.версия;
  const долгийОпросВторого = второй.запрос('/что-нового', { код: второй.код, пропуск: второй.пропуск, версия: версияВторого });
  долгийОпросВторого.catch(function () {});
  const долгийОпросТретьего = третий.запрос('/что-нового', { код: третий.код, пропуск: третий.пропуск, версия: версияТретьего });
  долгийОпросТретьего.catch(function () {});
  await жди(80);

  // Первый молчит — как перезагрузка телефона.
  комнаты.прибратьсяСейчас(Date.now() + комнаты.ПРОПАЛ_НАСОВСЕМ + 1000);

  const видВторогоДо = (await долгийОпросВторого).тело;
  const состояниеДо = видВторогоДо && видВторогоДо.состояние ? видВторогоДо.состояние : null;
  await долгийОпросТретьего.catch(function () { return null; });

  проверить(префикс + ': (а) второй ДО ожидания лимита видит слово «пропал-бот» (стол на троих — партия не закрывается)',
    Boolean(состояниеДо) && состояниеДо.видСобытия === 'пропал-бот',
    'видСобытия во виде второго: ' + JSON.stringify(состояниеДо && состояниеДо.видСобытия));
  проверить(префикс + ': стол на троих — партия продолжается, а не закрывается (этап «игра»)',
    Boolean(состояниеДо) && состояниеДо.этап === 'игра',
    'этап во виде второго сразу после пропажи: ' + JSON.stringify(состояниеДо && состояниеДо.этап));

  // Ждём НАСТОЯЩЕЕ время: таймер просрочки — реальный setTimeout сервера,
  // прибратьсяСейчас его не подменяет и не ускоряет.
  const времяОжидания = ЛИМИТ_СЕКУНД * 1000 + 1500;
  const видВтороПосле = await второй.состояние();
  await жди(времяОжидания);
  const видПослеОжидания = await второй.состояние();
  const состояниеПосле = видПослеОжидания.тело && видПослеОжидания.тело.состояние
    ? видПослеОжидания.тело.состояние : null;

  проверить(префикс + ': (б) после ожидания лимита слово события — «ход-по-времени», а не «пропал-бот»',
    Boolean(состояниеПосле) && состояниеПосле.видСобытия === 'ход-по-времени',
    'видСобытия во виде второго после ожидания ' + времяОжидания + ' мс: ' +
      JSON.stringify(состояниеПосле && состояниеПосле.видСобытия) +
      (состояниеПосле && состояниеПосле.видСобытия === 'пропал-бот'
        ? ' — старое слово «пропал-бот» так и висит, сработалаПросрочка событие не переписала'
        : ''));

  проверить(префикс + ': (в) партия продолжается на том же столе (этап «игра», код комнаты не поменялся)',
    Boolean(состояниеПосле) && состояниеПосле.этап === 'игра' && состояниеПосле.код === кодКомнаты,
    'этап: ' + JSON.stringify(состояниеПосле && состояниеПосле.этап) +
      ', код: ' + JSON.stringify(состояниеПосле && состояниеПосле.код) + ' (было ' + кодКомнаты + ')');

  const рассказВторому = состояниеПосле ? состояниеПосле.событие : undefined;
  проверить(префикс + ': принудительный ход достался именно второму, а не другому месту (текст — «своя» половина)',
    typeof рассказВторому === 'string' && рассказВторому.indexOf('сделан за вас') !== -1,
    'текст события во виде второго: ' + JSON.stringify(рассказВторому) +
      ' — «чужая» половина здесь значила бы, что просрочку записали не на второго');

  // (г) — словарь слов проверяем напрямую, в обход сервера: так отдельно
  // видно, готов ли сам словарь, даже если событие почему-то не долетело.
  const словоГ = партииМодуль.видСобытия({ что: 'ход-по-времени' });
  const текстГ = партииМодуль.текстСобытия({ что: 'ход-по-времени', кто: 'человек' }, 'человек', [], false);
  проверить(префикс + ': (г) словарь server/партия-по-сети.js знает слово «ход-по-времени» и даёт непустой текст',
    словоГ === 'ход-по-времени' && typeof текстГ === 'string' && текстГ.length > 0,
    'видСобытия(...) = ' + JSON.stringify(словоГ) + ', текстСобытия(...) = ' + JSON.stringify(текстГ));
}

/**
 * Ядро проверки: обрыв связи первого посреди партии на РЕАЛЬНЫЙ срок
 * (эмулируем через комнаты.прибратьсяСейчас с будущим временем — тот же
 * код, что и настоящий уборщик по таймеру, просто без ожидания вживую)
 * и возврат тем же кодом и пропуском.
 *
 * префикс — короткая подпись сценария для имён проверок в общем списке.
 */
async function сценарийДолгогоОбрыва(адрес, комнаты, префикс) {
  const { первый, второй } = await свестиДвоих(адрес);

  проверить(префикс + ': партия стартовала сама, без кнопки «Начать»',
    Boolean(первый.вид) && первый.вид.этап === 'игра',
    'этап после входа второго: ' + (первый.вид && первый.вид.этап));

  const кодКомнаты = первый.код;
  const рукаДо = JSON.stringify(первый.вид.мояРука);

  // Второй держит ОТКРЫТЫЙ длинный опрос («что нового») ровно в момент
  // скачка времени. Это ЕДИНСТВЕННОЕ, что реально защищает его от той же
  // метки «давно молчал»: в прибратьсяСейчас есть строка
  // «if (ждётСейчас(комната, ктоЯ)) continue» — она пропускает того, у кого
  // висит опрос, НЕЗАВИСИМО от часов последнего запроса. Простой «свежий
  // запрос до скачка» тут не спас бы: у обоих игроков последнийЗапрос был
  // бы плюс-минус одной и той же секундой, и скачок на 3+ минуты вперёд
  // «состарил» бы молчание обоих совершенно одинаково.
  await второй.состояние();
  const версияВторого = второй.вид && второй.вид.версия;
  const долгийОпрос = второй.запрос('/что-нового', { код: второй.код, пропуск: второй.пропуск, версия: версияВторого });
  долгийОпрос.catch(function () {});
  await жди(80);   // дать серверу принять запрос и записать второго в «ждущие», прежде чем скакнём во времени

  // Первый же с этой секунды не шлёт ничего вовсе — ровно то, что делает
  // перезагрузка телефона: соединение рвётся молча, без «Выйти».
  // Уборщик «смотрит на часы» почти через три минуты вперёд — секунду
  // сверху, чтобы наверняка перейти порог ПРОПАЛ_НАСОВСЕМ.
  комнаты.прибратьсяСейчас(Date.now() + комнаты.ПРОПАЛ_НАСОВСЕМ + 1000);

  // Проверяем именно ЭТУ комнату по коду (состояниеСтола не трогает
  // игроков и не может её случайно вернуть). Общий счётчик сколькоКомнат()
  // тут не годится: если до этого сценария уже гулял короткий обрыв, его
  // стол тоже стар по часам «последнийЗапрос» и уборщик сносит его в тот же
  // проход — общее число комнат тогда падает, хотя проверяемая нами
  // комната цела. Так и было обнаружено при первом прогоне этой проверки.
  const столЕщёЕсть = комнаты.состояниеСтола(кодКомнаты);
  проверить(префикс + ': именно эту комнату не снесло, пока первый молчал',
    Boolean(столЕщёЕсть && столЕщёЕсть.есть),
    'состояниеСтола(' + кодКомнаты + ') = ' + JSON.stringify(столЕщёЕсть));

  // Открытый опрос будит именно «выйти» → «разбудить» — второй получает
  // весть о пропаже первого мгновенно, БЕЗ нового запроса со своей стороны.
  const видВторогоПослеУхода = await долгийОпрос;
  const второйВидитУход = Boolean(видВторогоПослеУхода.тело && видВторогоПослеУхода.тело.состояние &&
    видВторогоПослеУхода.тело.состояние.соперникУшёл === true);
  проверить(префикс + ': второй (держал открытый опрос) узнаёт о пропаже первого сам, без нового вопроса',
    видВторогоПослеУхода.статус === 200 && второйВидитУход,
    'ответ долгого опроса второму: ' + JSON.stringify(видВторогоПослеУхода.тело));

  /* Слово события. Двое за столом — партия кончается без победителя,
     и уходящее место называется 'пропал' (не 'пропал-бот': бота сажать
     некуда, играть за столом больше некому). Ноль/undefined — провал,
     а не «поле новое, пропустим», см. правило «ноль найденного — провал». */
  const видСобытияВторого = видВторогоПослеУхода.тело && видВторогоПослеУхода.тело.состояние
    ? видВторогоПослеУхода.тело.состояние.видСобытия : undefined;
  проверить(префикс + ': второй видит слово события «пропал» (стол вдвоём — не «пропал-бот»)',
    видСобытияВторого === 'пропал',
    'видСобытия во виде второго: ' + JSON.stringify(видСобытияВторого));

  /* Слова оставшемуся — из того же ответа, поле «событие» (его собирает
     показатьИгроку через играКомнаты(комната).текстСобытия(...), словарь —
     РАССКАЗ_О_СОБЫТИИ в server/партия-по-сети.js). Решение владельца 21.09:
     три минуты молчания не убираем, но честно пишем «не дождался», а не
     путаем это с добровольным «Выйти». */
  const рассказВторому = видВторогоПослеУхода.тело && видВторогоПослеУхода.тело.состояние
    ? видВторогоПослеУхода.тело.состояние.событие : undefined;
  /* Проверено по настоящему словарю (РАССКАЗ_О_СОБЫТИИ в
     server/партия-по-сети.js): «не дождался» звучит только в СВОЕЙ
     половине — её слышит сам пропавший, когда вернётся. Второй (чужая
     половина) слышит «пропадает со связи слишком надолго…», и «слишком» —
     ровно то слово, которого нет ни в 'ушёл', ни в 'ушёл-бот' (там просто
     «выходит из игры»). Поэтому маркер для ВТОРОГО — «слишком», а не
     «не дождался»: выдумывать совпадение с чужой половиной — соврать
     в проверке. */
  проверить(префикс + ': слова оставшемуся о пропаже — про «слишком» долгое молчание (не тихий уход)',
    typeof рассказВторому === 'string' && рассказВторому.indexOf('слишком') !== -1,
    'текст события во виде второго: ' + JSON.stringify(рассказВторому));

  // Возврат: тем же кодом и тем же пропуском, без какой-либо особой двери.
  const возврат = await первый.состояние();
  проверить(префикс + ': первый вернулся тем же кодом и пропуском (200, не 404)',
    возврат.статус === 200,
    'сервер ответил ' + возврат.статус + ': ' + JSON.stringify(возврат.тело));

  const сталАТаЖеКомната = возврат.тело && возврат.тело.состояние &&
    возврат.тело.состояние.код === кодКомнаты;
  проверить(префикс + ': это тот же стол, а не новая раздача (код комнаты не поменялся)',
    Boolean(сталАТаЖеКомната),
    'было ' + кодКомнаты + ', стало ' + (возврат.тело && возврат.тело.состояние && возврат.тело.состояние.код));

  const второйЖивПослеВозврата = await второй.состояние();
  проверить(префикс + ': второго при возврате первого не выкинуло',
    второйЖивПослеВозврата.статус === 200,
    'сервер ответил второму ' + второйЖивПослеВозврата.статус + ': ' + JSON.stringify(второйЖивПослеВозврата.тело));

  // Не проверка, а честная запись факта — идёт в отчёт, не в счёт провалов.
  const этапПослеВозврата = возврат.тело && возврат.тело.состояние && возврат.тело.состояние.этап;
  const рукаПослеВозврата = возврат.тело && возврат.тело.состояние
    ? JSON.stringify(возврат.тело.состояние.мояРука) : undefined;
  return {
    этапПослеВозврата: этапПослеВозврата,
    рукаТаЖе: рукаПослеВозврата === рукаДо,
    рукаДо: рукаДо,
    рукаПослеВозврата: рукаПослеВозврата
  };
}

/**
 * Более лёгкий обрыв — меньше МОЛЧАНИЕ_ЭТО_ОБРЫВ (12 с), задолго до
 * трёхминутного «пропал насовсем». Для сравнения: тут возврат тривиален
 * (игрок ни разу не считался «ушедшим»), партия продолжается как ни
 * в чём не бывало — это база, отталкиваясь от которой видна разница
 * с настоящим долгим обрывом выше.
 */
async function сценарийКороткогоОбрыва(адрес, комнаты) {
  const { первый, второй } = await свестиДвоих(адрес);
  const рукаДо = JSON.stringify(первый.вид.мояРука);

  комнаты.прибратьсяСейчас(Date.now() + комнаты.МОЛЧАНИЕ_ЭТО_ОБРЫВ + 1000);

  const видВторого = await второй.состояние();
  проверить('короткий обрыв: соперник помечен «не на связи», но не «ушёл»',
    Boolean(видВторого.тело && видВторого.тело.состояние &&
      видВторого.тело.состояние.соперникНаСвязи === false &&
      !видВторого.тело.состояние.соперникУшёл),
    'вид второго: ' + JSON.stringify(видВторого.тело));

  const возврат = await первый.состояние();
  проверить('короткий обрыв: партия продолжается с того же места (этап «игра»)',
    возврат.статус === 200 && возврат.тело.состояние.этап === 'игра',
    'ответ: ' + JSON.stringify(возврат.тело));
  проверить('короткий обрыв: карты в руке те же, что были',
    JSON.stringify(возврат.тело.состояние.мояРука) === рукаДо,
    'было ' + rукаДоБезопасно(рукаДо) + ', стало ' + rукаДоБезопасно(JSON.stringify(возврат.тело.состояние.мояРука)));
}

function rукаДоБезопасно(с) { return typeof с === 'string' ? с.slice(0, 200) : String(с); }

/**
 * Контраст с «пропал»: тот же стол вдвоём, но первый нажимает «Выйти»
 * сам — по своей воле, а не из-за молчащей связи. Соперник обязан
 * услышать ДРУГОЕ слово события: 'ушёл', а не 'пропал' — иначе никто
 * не отличит честный уход от вынужденной пропажи (решение владельца
 * 21.09 именно про эту разницу).
 */
async function сценарийДобровольногоУхода(адрес) {
  const { первый, второй } = await свестиДвоих(адрес);
  await первый.выйти();

  const видВторого = await второй.состояние();
  const видСобытияВторого = видВторого.тело && видВторого.тело.состояние
    ? видВторого.тело.состояние.видСобытия : undefined;
  проверить('добровольный уход: соперник видит слово «ушёл», а не «пропал»',
    видСобытияВторого === 'ушёл',
    'видСобытия во виде второго: ' + JSON.stringify(видСобытияВторого));

  const рассказВторому = видВторого.тело && видВторого.тело.состояние
    ? видВторого.тело.состояние.событие : undefined;
  // Тот же маркер «слишком», что и в сценарии пропажи — здесь его быть
  // не должно: уход честный, а не вынужденный (см. комментарий выше).
  проверить('добровольный уход: слова сопернику НЕ говорят про «слишком» долгое молчание',
    typeof рассказВторому === 'string' && рассказВторому.indexOf('слишком') === -1,
    'текст события во виде второго: ' + JSON.stringify(рассказВторому));
}

/**
 * П.1 + П.2 ревьюера, одним сценарием на столе-компании (нужен именно он —
 * см. комментарий у свестиДвоихКомпанией, — иначе список «застолом» и поле
 * «неДождался» в ответе вообще не появятся).
 *
 * Второй молчит, сторож выводит его (стол вдвоём — партия закрывается без
 * победителя, этап 'конец'), первый видит «пропал» и честные значения поля
 * «неДождался». Второй тут же стучится обратно тем же кодом и пропуском —
 * ДО правки вернутьЗаСтол в этот момент писала событие 'вернулся' поверх
 * 'пропал', и первый при повторном опросе читал бы «Второй вышел». Проверяем
 * это буквально: первый СНОВА спрашивает вид уже ПОСЛЕ возврата второго.
 */
async function сценарийВозвратПослеЗакрытияПартии(адрес, комнаты, префикс) {
  const { первый, второй } = await свестиДвоихКомпанией(адрес);
  const кодКомнаты = первый.код;

  // Первый держит открытый долгий опрос — тот же приём, что и выше:
  // иначе скачок времени состарит молчание не только второго, но и его.
  const версияПервого = первый.вид && первый.вид.версия;
  const долгийОпрос = первый.запрос('/что-нового', { код: первый.код, пропуск: первый.пропуск, версия: версияПервого });
  долгийОпрос.catch(function () {});
  await жди(80);

  // Второй с этой секунды молчит — перезагрузка телефона.
  комнаты.прибратьсяСейчас(Date.now() + комнаты.ПРОПАЛ_НАСОВСЕМ + 1000);

  const видДоВозврата = (await долгийОпрос).тело;
  const состояниеДо = видДоВозврата && видДоВозврата.состояние ? видДоВозврата.состояние : null;

  проверить(префикс + ': первый видит «пропал» ДО возврата второго',
    Boolean(состояниеДо) && состояниеДо.видСобытия === 'пропал',
    'видСобытия во виде первого: ' + JSON.stringify(состояниеДо && состояниеДо.видСобытия));

  const своёМестоДо = местоВЗастолом(состояниеДо, true);
  const местоВторогоДо = местоВЗастолом(состояниеДо, false);
  проверить(префикс + ': поле «неДождался» ДО возврата — у места второго ушёл===true и неДождался===true',
    Boolean(местоВторогоДо) && местоВторогоДо.ушёл === true && местоВторогоДо.неДождался === true,
    'место второго во виде первого: ' + JSON.stringify(местоВторогоДо));
  проверить(префикс + ': поле «неДождался» ДО возврата — у СВОЕГО места первого неДождался===false (поле есть, не undefined)',
    Boolean(своёМестоДо) && своёМестоДо.неДождался === false,
    'своё место во виде первого: ' + JSON.stringify(своёМестоДо));

  // Второй стучится обратно тем же кодом и пропуском.
  const возвратВторого = await второй.состояние();
  проверить(префикс + ': второй вернулся тем же кодом и пропуском (200, не 404)',
    возвратВторого.статус === 200,
    'сервер ответил ' + возвратВторого.статус + ': ' + JSON.stringify(возвратВторого.тело));

  // Первый СНОВА спрашивает вид — вот он, пункт из отчёта ревьюера.
  const видПослеВозврата = await первый.состояние();
  const состояниеПосле = видПослеВозврата.тело && видПослеВозврата.тело.состояние
    ? видПослеВозврата.тело.состояние : null;

  проверить(префикс + ': ПОСЛЕ возврата второго первый по-прежнему видит «пропал», а не «вернулся»',
    Boolean(состояниеПосле) && состояниеПосле.видСобытия === 'пропал',
    'видСобытия во виде первого после возврата: ' + JSON.stringify(состояниеПосле && состояниеПосле.видСобытия));

  проверить(префикс + ': и слова остались прежними — про «слишком» долгое молчание, не про возврат',
    Boolean(состояниеПосле) && typeof состояниеПосле.событие === 'string' && состояниеПосле.событие.indexOf('слишком') !== -1,
    'текст события во виде первого после возврата: ' + JSON.stringify(состояниеПосле && состояниеПосле.событие));

  const местоВторогоПосле = местоВЗастолом(состояниеПосле, false);
  проверить(префикс + ': поле «неДождался» ПОСЛЕ возврата — у места второго ушёл===false и неДождался===false',
    Boolean(местоВторогоПосле) && местоВторогоПосле.ушёл === false && местоВторогоПосле.неДождался === false,
    'место второго во виде первого после возврата: ' + JSON.stringify(местоВторогоПосле));

  проверить(префикс + ': код комнаты не поменялся — это тот же стол, а не новая раздача',
    Boolean(состояниеПосле) && состояниеПосле.код === кодКомнаты,
    'было ' + кодКомнаты + ', стало ' + (состояниеПосле && состояниеПосле.код));
}

