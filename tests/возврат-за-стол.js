/* -----------------------------------------------------------------------
   Обход НЕЗАКОММИЧЕННОЙ поломки js/game.js: рабочее дерево прямо сейчас
   присваивает `window.ДуракЛобби = ...` без охраны `typeof window`, и это
   роняет require('js/game.js') в Node ЛЮБЫМ способом — и require в тесте,
   и «node server/сервер.js» напрямую. Проверено отдельно: HEAD (последний
   коммит) от этой беды свободен — там та же строка стоит под
   `if (typeof window !== 'undefined')`. Поэтому копия для проверки берёт
   js/game.js из HEAD, если рабочая версия не грузится, — иначе ни один
   серверный сценарий вообще не запустить. Отдельная находка об этом —
   в отчёте, файл game.js эта проверка не трогает НИГДЕ, кроме temp-копии.
   ----------------------------------------------------------------------- */

function файлЛомаетRequire(файл) {
  try {
    execFileSync(process.execPath, ['-e', 'require(process.argv[1]);', файл], { stdio: 'pipe' });
    return false;
  } catch (сбой) {
    return true;
  }
}

/** Копия server/ и js/ во временную папку — «портим» и требуем только там. */
function подготовитьРабочуюКопию() {
  const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'возврат-за-стол-'));
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(врем, 'server'), { recursive: true });
  fs.cpSync(path.join(КОРЕНЬ, 'js'), path.join(врем, 'js'), { recursive: true });

  const копияGame = path.join(врем, 'js', 'game.js');
  if (файлЛомаетRequire(копияGame)) {
    const изHEAD = execFileSync('git', ['show', 'HEAD:js/game.js'], { cwd: КОРЕНЬ, encoding: 'utf8' });
    fs.writeFileSync(копияGame, изHEAD, 'utf8');
    console.log('! Рабочее дерево js/game.js сейчас ломает require (window без охраны) —');
    console.log('  копия для проверки взяла js/game.js из последнего коммита (HEAD). См. находку в отчёте.');
  }
  return врем;
}

