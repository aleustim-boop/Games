/* -----------------------------------------------------------------------
   Ломающий прогон №1: портит копию сервера во временной папке и требует
   провала — если комнату уборщик сносит РАНЬШЕ срока (испорченный
   ЖИЗНЬ_БРОШЕННОЙ_КОМНАТЫ), возврат первого обязан получить 404 вместо
   200, а второй — тоже потерять стол. Это ровно тот риск, из-за которого
   весь сценарий проверяется: «забыли живую комнату — друзья ждут зря».
   ----------------------------------------------------------------------- */

function подготовитьИспорченнуюКопию() {
  const врем = подготовитьРабочуюКопию();

  const файлКомнат = path.join(врем, 'server', 'комнаты.js');
  const исходник = fs.readFileSync(файлКомнат, 'utf8');
  const было = 'const ЖИЗНЬ_БРОШЕННОЙ_КОМНАТЫ = 15 * 60 * 1000;';
  if (исходник.indexOf(было) === -1) {
    throw new Error('не нашёл строку для порчи (ЖИЗНЬ_БРОШЕННОЙ_КОМНАТЫ) — код сервера изменился, поправьте tests/возврат-за-стол.js');
  }
  const испорчено = исходник.replace(было,
    'const ЖИЗНЬ_БРОШЕННОЙ_КОМНАТЫ = 1000; /* ИСПОРЧЕНО ПРОВЕРКОЙ tests/возврат-за-стол.js --сломать */');
  fs.writeFileSync(файлКомнат, испорчено, 'utf8');
  return врем;
}

/* -----------------------------------------------------------------------
   Ломающий прогон №2: подменяет само СЛОВО события. В настоящей строке
   server/комнаты.js записатьСобытие(комната, ктоЯ, заМолчание === true
   ? 'пропал' : 'ушёл') решает, вывели ли молчание или человек ушёл сам.
   Стираем это решение — оставляем всегда 'ушёл'. Живой стол по-прежнему
   цел и второй по-прежнему узнаёт об уходе (те проверки должны остаться
   зелёными), а вот СЛОВО и СЛОВА про «не дождался» обязаны покраснеть:
   ровно это владелец просил не путать 21.09.
   ----------------------------------------------------------------------- */

function подготовитьИспорченнуюКопиюСлов() {
  const врем = подготовитьРабочуюКопию();

  const файлКомнат = path.join(врем, 'server', 'комнаты.js');
  const исходник = fs.readFileSync(файлКомнат, 'utf8');
  const было = "заМолчание === true ? 'пропал' : 'ушёл'";
  const сколькоРаз = исходник.split(было).length - 1;
  if (сколькоРаз !== 1) {
    throw new Error('строка для порчи слова встретилась ' + сколькоРаз +
      ' раз(а) вместо ровно одного — код сервера изменился, поправьте tests/возврат-за-стол.js');
  }
  const испорчено = исходник.replace(было,
    "'ушёл' /* ИСПОРЧЕНО ПРОВЕРКОЙ tests/возврат-за-стол.js --сломать-слово: было заМолчание === true ? 'пропал' : 'ушёл' */");
  fs.writeFileSync(файлКомнат, испорчено, 'utf8');
  return врем;
}

/* -----------------------------------------------------------------------
   Ломающий прогон №3 (--сломать-возврат): убирает саму проверку этапа,
   П.1 ревьюера. Строка вернутьЗаСтол «if (комната.этап !== 'конец') {
   записатьСобытие(...,'вернулся'); }» превращается в безусловную запись —
   ровно то поведение, что было ДО правки. Живой стол по-прежнему цел
   (второй по-прежнему может вернуться, 200), а вот видСобытия ПОСЛЕ
   возврата обязано покраснеть: событие 'пропал' будет затёрто на
   'вернулся', и та же строка обязана покраснеть при чтении исходника
   из этой самой испорченной копии.
   ----------------------------------------------------------------------- */

function подготовитьИспорченнуюКопиюВозврата() {
  const врем = подготовитьРабочуюКопию();

  const файлКомнат = path.join(врем, 'server', 'комнаты.js');
  const исходник = fs.readFileSync(файлКомнат, 'utf8');
  const было = "  if (комната.этап !== 'конец') {\n    записатьСобытие(комната, место, 'вернулся');\n  }\n";
  if (исходник.indexOf(было) === -1) {
    throw new Error('не нашёл строку для порчи (проверка этапа перед "вернулся" в вернутьЗаСтол) — код сервера изменился, поправьте tests/возврат-за-стол.js');
  }
  const испорчено = исходник.replace(было,
    "  записатьСобытие(комната, место, 'вернулся'); /* ИСПОРЧЕНО ПРОВЕРКОЙ tests/возврат-за-стол.js --сломать-возврат: убрана проверка «этап !== 'конец'» */\n");
  fs.writeFileSync(файлКомнат, испорчено, 'utf8');
  return врем;
}

/* -----------------------------------------------------------------------
   Ломающий прогон №4 (--сломать-поле): убирает само поле «неДождался» из
   ответа сервера (server/партия-по-сети.js, список «застолом»). Живой стол
   по-прежнему цел, слово события «пропал» и слова про «слишком» никуда не
   деваются (они собираются из другого места) — а вот три сверки именно
   поля «неДождался» (ДО возврата у второго, ДО возврата у СВОЕГО места,
   ПОСЛЕ возврата) обязаны покраснеть: там, где ждали true/false, окажется
   undefined. Заодно красным падает прямое чтение той же строки в
   проверкаВозвратаЗаСтолВИсходнике — по этой самой испорченной копии.
   ----------------------------------------------------------------------- */

function подготовитьИспорченнуюКопиюПоля() {
  const врем = подготовитьРабочуюКопию();

  const файлПартии = path.join(врем, 'server', 'партия-по-сети.js');
  const исходник = fs.readFileSync(файлПартии, 'utf8');
  // Файл на CRLF (в отличие от комнаты.js на LF) — перенос строки берём
  // из самого исходника, чтобы не промахнуться мимо строки.
  const переносСтрок = исходник.indexOf('\r\n') !== -1 ? '\r\n' : '\n';
  const было = '      неДождался: место.выбылЗаМолчание === true,' + переносСтрок;
  if (исходник.indexOf(было) === -1) {
    throw new Error('не нашёл строку для порчи (поле «неДождался» в показатьИгроку) — код сервера изменился, поправьте tests/возврат-за-стол.js');
  }
  // Текст пометки нарочно НЕ повторяет точную подстроку 'неДождался: место.выбылЗаМолчание === true'
  // (её ищет проверкаВозвратаЗаСтолВИсходнике) — иначе комментарий сам бы прятал поломку от проверки.
  const испорчено = исходник.replace(было,
    '      /* ИСПОРЧЕНО ПРОВЕРКОЙ tests/возврат-за-стол.js --сломать-поле: убрано поле «неДождался» (было место.выбылЗаМолчание) */' + переносСтрок);
  fs.writeFileSync(файлПартии, испорчено, 'utf8');
  return врем;
}

/* -----------------------------------------------------------------------
   Ломающий прогон №5 (--сломать-просрочка): вырезает из КОПИИ server/комнаты.js
   вызов записатьСобытие(комната, кто, 'ход-по-времени') внутри сработалаПросрочка.
   Принудительный ход по-прежнему делается (правила.ходПоПросрочке остаётся
   нетронутым), но событие о нём никуда не записывается — старое слово
   ('пропал-бот' в нашем сценарии) обязано провисеть и после ожидания.
   Красным должен упасть именно пункт (б); (а) и (в) остаются целы — они
   не зависят от того, пишется ли НОВОЕ событие.
   Регулярка ищет вызов ГИБКО (не по именам переменных вокруг), потому что
   после дальнейших правок разработчика имена могут поменяться, а вот сам
   вызов с словом 'ход-по-времени' внутри — обязателен по договору задания.
   Нашла ноль совпадений — это провал самой порчи, а не тихий пропуск:
   значит строки для порчи в файле ещё нет вовсе (см. правило «ноль
   найденного — провал»).
   ----------------------------------------------------------------------- */

function подготовитьИспорченнуюКопиюПросрочки() {
  const врем = подготовитьРабочуюКопию();

  const файлКомнат = path.join(врем, 'server', 'комнаты.js');
  const исходник = fs.readFileSync(файлКомнат, 'utf8');
  const регулярка = /записатьСобытие\([^)]*'ход-по-времени'[^)]*\)\s*;?/;
  const совпадение = исходник.match(регулярка);
  if (!совпадение) {
    throw new Error('строка не найдена: в server/комнаты.js нет вызова записатьСобытие(...) со словом ' +
      "'ход-по-времени' — код сработалаПросрочка изменился или правка ещё не внесена, поправьте tests/возврат-за-стол.js");
  }
  const испорчено = исходник.replace(совпадение[0],
    '/* ИСПОРЧЕНО ПРОВЕРКОЙ tests/возврат-за-стол.js --сломать-просрочка: событие ход-по-времени не пишем */');
  fs.writeFileSync(файлКомнат, испорчено, 'utf8');
  return врем;
}

function убратьВременную(врем) {
  fs.rmSync(врем, { recursive: true, force: true });
}

