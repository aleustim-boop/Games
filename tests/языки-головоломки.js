  let всеОк = true;
  for (const игра of игры) всеОк = ломатьИгру(игра, арг[1]) && всеОк;
  console.log(всеОк ? 'ЛОМАЮЩИЙ ЗАПУСК: проверка честно краснеет' : 'ЛОМАЮЩИЙ ЗАПУСК: проверка НЕ краснеет — она слепая');
