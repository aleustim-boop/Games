/* =====================================================================
   Постоянная проверка: сервер сам называет, чьё кресло положило атаку
   и чьё — защиту у каждой пары на столе компанией («чьяАтака»/«чьяЗащита»),
   плюс поле «парыМест». Перенесена из временного скрипта разработчика
   (коммит 739838f, был во временной папке сессии — «проверка-кто-положил.js»)
   в постоянную папку tests/, как требует правило проекта: проверка живёт
   рядом с кодом и умеет краснеть.

   Партия играется на 4 места прямо через функции server/партия-по-сети.js,
   без комнаты и без сети — так же, как это делают другие проверки в этой
   папке (см. tests/автопрогон-правил-компанией.js).

   Запуск:
       node tests/кто-положил-карту-сервер.js
   Ломающий прогон (проверить, что тест умеет краснеть):
       node tests/кто-положил-карту-сервер.js --сломать
   «--сломать» сдвигает записанное сервером кресло на соседнее (по кругу
   из 4) прямо в памяти проверки, не трогая сервер и не трогая диск —
   и сверка обязана заметить подмену.
   ===================================================================== */
const path = require('path');
const сеть = require(path.join(__dirname, '..', 'server', 'партия-по-сети.js'));
const правила = require(path.join(__dirname, '..', 'js', 'game.js'));

const ЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;
if (ЛОМАТЬ) {
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: записанное кресло сдвигается на соседнее — проверка обязана покраснеть ***');
}

let провалов = 0;
let проверок = 0;

/** В ломающем запуске подменяем кресло на соседнее (по кругу из 4). Иначе — как есть. */
function испортить(кресло) {
  if (!ЛОМАТЬ || кресло === null || кресло === undefined) return кресло;
  return (кресло % 4) + 1;
}

function сверить(имя, ожидаемоеКресло, фактическоеКресло) {
  проверок++;
  const факт = испортить(фактическоеКресло);
  const ок = факт === ожидаемоеКресло;
  if (!ок) провалов++;
  console.log((ок ? 'ок    ' : 'ПЛОХО ') + имя + ': ждали кресло ' + ожидаемоеКресло + ', получили ' + факт);
}

function проверить(да, слова) {
  проверок++;
  if (!да) провалов++;
  console.log((да ? 'ок    ' : 'ПЛОХО ') + слова);
}

/* ---------------------------------------------------------------------
   Часть 1. Партия на 4 места: играем и после каждого одиночного хода
   сверяем чьяАтака/чьяЗащита новой или изменившейся пары с тем, у кого
   реально убыла карта из руки.
   --------------------------------------------------------------------- */

const местаСтола = сеть.МЕСТА.slice(0, 4).map(function (ключ, н) {
  return { ключ: ключ, имя: 'Место ' + (н + 1), этоБот: false,
           хозяин: н === 0, наСвязи: true, ушёл: false, хочетЕщё: false };
});

function видКомпанией(партия) {
  return сеть.видДляИгрока(партия, партия.игроки[0], { места: местаСтола });
}

function рукиСейчас(партия) {
  const р = {};
  for (const место of партия.игроки) р[место] = (партия.руки[место] || []).length;
  return р;
}

/** Единственное место, у которого рука уменьшилась, — или null. */
function ктоПотерялКарту(до, после) {
  const потерявшие = Object.keys(до).filter(function (место) {
    return (после[место] || 0) < до[место];
  });
  return потерявшие.length === 1 ? потерявшие[0] : null;
}

function найтиНеотбитую(партия) {
  for (let н = 0; н < партия.стол.length; н++) {
    if (!партия.стол[н].защита) return { индекс: н, карта: партия.стол[н] };
  }
  return null;
}

/** Есть ли где-то за столом возможность бросить заходную вне очереди. */
function найтиВозможностьБросить(партия) {
  if (партия.стол.length === 0) return null;
  for (const место of партия.игроки) {
    const рука = партия.руки[место] || [];
    for (let i = 0; i < рука.length; i++) {
      if (правила.можноПодхватить(партия, место, рука[i])) return { место: место, индекс: i };
    }
  }
  return null;
}

/**
 * Выполнить одно действие (через любую из дверей — «сделатьХод», «ходЗаБота»
 * или «подхватЗаБота») и, если в результате у кого-то убыла карта, сверить
 * записанное сервером кресло с тем, кто её на самом деле положил.
 */
function проверитьДействие(партия, имя, выполнить) {
  const рукиДо = рукиСейчас(партия);
  const парНаСтолеДо = партия.стол.length;
  const защищеныДо = партия.стол.map(function (п) { return Boolean(п.защита); });

  const результат = выполнить();
  if (!результат || результат.принято === false) {
    провалов++;
    console.log('ПЛОХО ' + имя + ': действие не приняли — ' + JSON.stringify(результат));
    return результат;
  }

  const рукиПосле = рукиСейчас(партия);
  const ктоПотерял = ктоПотерялКарту(рукиДо, рукиПосле);
  if (!ктоПотерял) return результат;   // «беру»/«бито» — карту в атаку не клали, сверять нечего

  const ожидаемоеКресло = сеть.номерМеста(ктоПотерял);
  const вид = видКомпанией(партия);
  if (партия.стол.length > парНаСтолеДо) {
    const пара = вид.стол[вид.стол.length - 1];
    сверить(имя + ' — атака', ожидаемоеКресло, пара.чьяАтака);
  } else {
    let нашли = false;
    for (let н = 0; н < вид.стол.length; н++) {
      if (вид.стол[н].защита && !защищеныДо[н]) {
        сверить(имя + ' — защита', ожидаемоеКресло, вид.стол[н].чьяЗащита);
        нашли = true;
        break;
      }
    }
    if (!нашли) { провалов++; console.log('ПЛОХО ' + имя + ': не нашли изменившуюся пару на столе'); }
  }
  return результат;
}

const типыДействий = {
  ход: false, перевод: false, подкидывание: false, отбой: false,
  беру: false, бито: false, ходБота: false, бросокВнеОчереди: false
};

function автоХодЧеловека(партия, место) {
  const фаза = правила.фаза(партия);
  const рука = партия.руки[место];
  const имя = 'место ' + сеть.номерМеста(место);

  if (фаза === 'атака') {
    типыДействий.ход = true;
    return проверитьДействие(партия, 'ход (' + имя + ')', function () {
      return сеть.сделатьХод(партия, место, { действие: 'ходить', карта: 0 });
    });
  }
  if (фаза === 'защита') {
    if (партия.переводной) {
      for (let i = 0; i < рука.length; i++) {
        if (правила.можноПеревести(партия, рука[i])) {
          типыДействий.перевод = true;
          return проверитьДействие(партия, 'перевод (' + имя + ')', function () {
            return сеть.сделатьХод(партия, место, { действие: 'перевести', карта: i });
          });
        }
      }
    }
    const неотбитая = найтиНеотбитую(партия);
    for (let i = 0; i < рука.length; i++) {
      if (неотбитая && правила.бьёт(рука[i], неотбитая.карта.атака, партия.козырь)) {
        типыДействий.отбой = true;
        return проверитьДействие(партия, 'отбить (' + имя + ')', function () {
          return сеть.сделатьХод(партия, место, { действие: 'отбить', пара: неотбитая.индекс, карта: i });
        });
      }
    }
    типыДействий.беру = true;
    return проверитьДействие(партия, 'беру (' + имя + ')', function () {
      return сеть.сделатьХод(партия, место, { действие: 'беру' });
    });
  }
  // подкидывание / докидывание
  for (let i = 0; i < рука.length; i++) {
    if (правила.можноПоложить(партия, рука[i])) {
      типыДействий.подкидывание = true;
      return проверитьДействие(партия, 'подкинуть (' + имя + ')', function () {
        return сеть.сделатьХод(партия, место, { действие: 'ходить', карта: i });
      });
    }
  }
  типыДействий.бито = true;
  return проверитьДействие(партия, 'бито (' + имя + ')', function () {
    return сеть.сделатьХод(партия, место, { действие: 'бито' });
  });
}

function автоХодБота(партия, место) {
  типыДействий.ходБота = true;
  return проверитьДействие(партия, 'ходЗаБота (место ' + сеть.номерМеста(место) + ')', function () {
    return сеть.ходЗаБота(партия, место, 1);
  });
}

function автоБросокВнеОчереди(партия, место, индекс) {
  типыДействий.бросокВнеОчереди = true;
  return проверитьДействие(партия, 'подхватЗаБота (место ' + сеть.номерМеста(место) + ')', function () {
    return сеть.подхватЗаБота(партия, место, индекс);
  });
}

function сыгратьПартию(номер) {
  const партия = сеть.начатьПартию(null, {
    игроки: сеть.МЕСТА.slice(0, 4),
    переводной: true
  });

  let итераций = 0;
  let брошеноВнеОчереди = 0;
  let ходовБота = 0;
  while (!партия.завершена && итераций < 500) {
    итераций++;

    // Изредка пробуем бросок вне очереди — не по правилу очереди, а по факту возможности.
    if (брошеноВнеОчереди < 2) {
      const бросок = найтиВозможностьБросить(партия);
      if (бросок) {
        автоБросокВнеОчереди(партия, бросок.место, бросок.индекс);
        брошеноВнеОчереди++;
        continue;
      }
    }

    const место = правила.ктоХодит(партия);
    if (!место) break;

    if (ходовБота < 4 && итераций % 5 === 0) {
      автоХодБота(партия, место);
      ходовБота++;
    } else {
      автоХодЧеловека(партия, место);
    }
  }

  проверить(партия.завершена, 'партия №' + номер + ' доиграна до конца (итераций ' + итераций + ')');
}

console.log('--- Часть 1: чьяАтака/чьяЗащита за несколько партий ---');
for (let н = 1; н <= 6; н++) сыгратьПартию(н);
console.log('охвачены виды действий: ' + JSON.stringify(типыДействий));
проверить(типыДействий.ход && типыДействий.подкидывание && типыДействий.отбой &&
  типыДействий.беру && типыДействий.бито && типыДействий.ходБота && типыДействий.бросокВнеОчереди,
  'все нужные виды действий встретились хоть раз (кроме перевода — он не гарантирован)');
if (!типыДействий.перевод) console.log('замечание: перевод ни разу не случился естественным путём в этом прогоне');

