async function дождаться(страница, экран, мс) {
  await страница.waitForFunction((и) => {
    const э = document.getElementById(и);
    return Boolean(э && э.classList.contains('экран--виден'));
  }, экран, { timeout: мс || 8000 });
}

/** Положить мок window.ЭкранДрузей — журнал вызовов копится в самой
    странице (window.__вызовыДрузей), читаем его page.evaluate'ом. */
async function поставитьМокЭкранаДрузей(страница) {
  await страница.evaluate(function () {
    window.__вызовыДрузей = [];
    window.ЭкранДрузей = {
      открыть: function () { window.__вызовыДрузей.push('открыть'); },
      открытьДобавление: function () { window.__вызовыДрузей.push('открытьДобавление'); }
    };
  });
}
async function вызовыДрузей(страница) {
  return страница.evaluate(function () { return window.__вызовыДрузей || []; });
}

async function именаВТаблице(страница) {
  return страница.locator('#рейтинг-таблица .рейтинг-имя').allTextContents();
}

