function постучать(адрес) {
  return new Promise(function (готово) {
    const з = http.get(адрес, function (о) { о.resume(); готово(о.statusCode); });
    з.on('error', () => готово(0));
    з.setTimeout(1500, function () { з.destroy(); готово(0); });
  });
}
async function дождатьсяСтраниц() {
  for (let п = 0; п < 40; п++) {
    if (await постучать(АДРЕС_СТРАНИЦ + '/index.html')) return true;
    await new Promise((г) => setTimeout(г, 150));
  }
  return false;
}

