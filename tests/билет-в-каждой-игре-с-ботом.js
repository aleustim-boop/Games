/* =====================================================================
   БИЛЕТ НА ОЧКИ ЗА ПАРТИЮ С БОТОМ — ЕСТЬ ЛИ ОН У КАЖДОЙ ИГРЫ (Э3.11).

   Простыми словами: партию с ботом сервер не видит, поэтому очки за
   неё идут через «билет» — экран игры берёт билет на старте партии
   (общее/js/очки-рейтинга.js → сервер) и сдаёт его на итоге. Эта проверка
   смотрит на КАЖДУЮ игру из реестра (общее/js/игры-реестр.js), у которой
   вообще есть бот, и спрашивает три вещи:
     1) экран игры (запись.бот.экран) и правда берёт и сдаёт билет;
     2) страница игры подключает дверь для билета;
     3) в способОчков записи есть слово 'билет' (иначе сервер billет
        не выдаст — см. server/билеты.js, собратьИгрыСБилетами()).

   ОСОБЫЙ СЛУЧАЙ — ДУРАК. У всех остальных игр билет берёт и сдаёт
   общий файл общее/js/очки-рейтинга.js (window.ОчкиРейтинга.взятьБилет/
   .сдать), и его же подключает страница игры. У дурака билет старше:
   он всё ещё живёт в игры/дурак/game.js и ходит через свою дверь общее/js/сеть.js
   (window.Сеть.билетНаБота(...) / window.Сеть.итогПартииСБотом(...)),
   а index.html вместо общее/js/очки-рейтинга.js подключает общее/js/сеть.js.
   Для «дурака» проверка ищет именно эти вызовы и это подключение —
   не потому что дурак сломан, а потому что он не переехал на общую
   дверь (задание Э3.11 требовало посмотреть, как реально написано
   в игры/дурак/game.js, и не считать это провалом).

   ДОЛГ — известные дыры с причиной. Игра из ДОЛГа печатается как
   «долг», а не провал, но список может только сокращаться: если игра
   из ДОЛГа уже всё делает правильно, а её не вычеркнули — это провал
   («вычеркни из ДОЛГа»).

   Ноль игр с ботом в реестре — сама по себе провал: значит реестр
   пуст или сломан, и проверять нечего.

   Запуск:
       node tests/билет-в-каждой-игре-с-ботом.js                  — проект
       node tests/билет-в-каждой-игре-с-ботом.js --корень=<папка> — другая папка
       node tests/билет-в-каждой-игре-с-ботом.js --сломать        — ломающий запуск:
         делает КОПИИ страниц, js/ во временной папке, портит их по одной
         и требует провала в каждом сценарии. Настоящие файлы не трогаются,
         копия удаляется сразу после прогона (даже если сценарий упал).
   ===================================================================== */

