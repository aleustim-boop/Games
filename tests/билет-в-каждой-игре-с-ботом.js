/* Игра дурака — особый путь: билет берёт и сдаёт общее/js/сеть.js изнутри
   игры/дурак/game.js, а не общий общее/js/очки-рейтинга.js (см. шапку файла). */
const ОСОБЫЙ_ПУТЬ_ДУРАКА = 'дурак';

function экранировать(текст) {
  return текст.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/* Текст без комментариев html и js — чтобы закомментированный «на потом»
   вызов не засчитался как настоящий. */
function безКомментариев(текст) {
  return текст
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:'"\\])\/\/[^\n]*/g, '$1');
}

function прочитать(КОРЕНЬ, относительныйПуть) {
  const полный = path.join(КОРЕНЬ, относительныйПуть);
  return fs.existsSync(полный) ? безКомментариев(fs.readFileSync(полный, 'utf8')) : null;
}

/* Скрипты страницы по порядку: только свои js/…, без хвоста ?v=. */
function скриптыСтраницы(html) {
  const список = [];
  const образец = /<script[^>]*\ssrc="((?:общее|игры)\/[^"?]+)(?:\?[^"]*)?"/g;
  let найдено;
  while ((найдено = образец.exec(html)) !== null) список.push(найдено[1]);
  return список;
}

/**
 * Чего не хватает у одной игры с ботом. Пустой список — всё в порядке.
 */
function чегоНеХватает(КОРЕНЬ, запись) {
  const нет = [];
  const ключ = запись.ключ;
  const особый = ключ === ОСОБЫЙ_ПУТЬ_ДУРАКА;

  const путьЭкрана = запись.бот && запись.бот.экран;
  if (!путьЭкрана) { нет.push('в записи реестра нет бот.экран'); return нет; }
  const текстЭкрана = прочитать(КОРЕНЬ, путьЭкрана);
  if (текстЭкрана === null) { нет.push('файла экрана ' + путьЭкрана); return нет; }

  if (особый) {
    if (текстЭкрана.indexOf('билетНаБота(') === -1) {
      нет.push('вызова взятия билета (Сеть.билетНаБота) в ' + путьЭкрана);
    }
    if (текстЭкрана.indexOf('итогПартииСБотом(') === -1) {
      нет.push('вызова сдачи билета (Сеть.итогПартииСБотом) в ' + путьЭкрана);
    }
  } else {
    const взять = new RegExp('ОчкиРейтинга\\.взятьБилет\\(\\s*[\'"]' + экранировать(ключ) + '[\'"]');
    if (!взять.test(текстЭкрана)) {
      нет.push('вызова ОчкиРейтинга.взятьБилет(\'' + ключ + '\', …) в ' + путьЭкрана);
    }
    if (текстЭкрана.indexOf('ОчкиРейтинга.сдать(') === -1) {
      нет.push('вызова ОчкиРейтинга.сдать(…) в ' + путьЭкрана);
    }
  }

  const html = запись.страница ? прочитать(КОРЕНЬ, запись.страница) : null;
  if (html === null) {
    нет.push('страницы ' + (запись.страница || '(не указана)'));
  } else {
    const скрипты = скриптыСтраницы(html);
    if (особый) {
      if (скрипты.indexOf('общее/js/сеть.js') === -1) {
        нет.push('подключения общее/js/сеть.js на странице ' + запись.страница + ' (у «дурака» билет идёт через неё, а не через общее/js/очки-рейтинга.js)');
      }
    } else if (скрипты.indexOf('общее/js/очки-рейтинга.js') === -1) {
      нет.push('подключения общее/js/очки-рейтинга.js на странице ' + запись.страница);
    }
  }

  if (!Array.isArray(запись.способОчков) || запись.способОчков.indexOf('билет') === -1) {
    нет.push('слова \'билет\' в способОчков записи реестра');
  }

  return нет;
}

/**
 * Проверить один корень (проект или копию). Возвращает счёт и провалы;
 * печатает построчно, если не «тихо».
 */
function проверитьКорень(КОРЕНЬ, тихо, допДолг) {
  const эффДолг = Object.assign({}, ДОЛГ, допДолг || {});
  const итог = { проверок: 0, провалы: [], вПорядке: 0, вДолгу: 0, вПорядкеСписок: [] };
  function сказать(т) { if (!тихо) console.log(т); }
  function проверить(условие, текстПровала) {
    итог.проверок++;
    if (!условие) { итог.провалы.push(текстПровала); сказать('  ПРОВАЛ: ' + текстПровала); }
    return условие;
  }

  let реестр = [];
  try {
    const путь = path.join(КОРЕНЬ, 'общее', 'js', 'игры-реестр.js');
    delete require.cache[path.resolve(путь)];
    реестр = require(путь).все();
  } catch (ошибка) {
    проверить(false, 'не читается общее/js/игры-реестр.js: ' + ошибка.message);
  }

  const сБотом = реестр.filter(function (и) { return !!и.бот; });
  проверить(сБотом.length > 0, 'в реестре нет ни одной игры с ботом — проверять нечего');

  сказать('Корень: ' + КОРЕНЬ);
  сказать('Игр с ботом: ' + сБотом.length + '\n');

  сБотом.forEach(function (запись) {
    const ключ = запись.ключ;
    const нет = чегоНеХватает(КОРЕНЬ, запись);
    const долг = Object.prototype.hasOwnProperty.call(эффДолг, ключ);
    if (!нет.length && !долг) {
      итог.вПорядке++;
      итог.вПорядкеСписок.push(ключ);
      проверить(true, '');
      сказать('ок     ' + ключ);
    } else if (!нет.length && долг) {
      сказать('?      ' + ключ);
      проверить(false, '«' + ключ + '» уже берёт и сдаёт билет по всем правилам, но всё ещё в списке ДОЛГ — вычеркните её оттуда');
    } else if (долг) {
      итог.вДолгу++;
      проверить(true, '');
      сказать('долг   ' + ключ + ' — ' + эффДолг[ключ]);
      сказать('         не хватает: ' + нет.join('; '));
    } else {
      сказать('плохо  ' + ключ);
      проверить(false, '«' + ключ + '» билет не берёт/не сдаёт по всем правилам, не хватает: ' + нет.join('; '));
    }
  });

  Object.keys(эффДолг).forEach(function (ключ) {
    проверить(сБотом.some(function (и) { return и.ключ === ключ; }),
      'в ДОЛГе «' + ключ + '», но такой игры с ботом нет в реестре');
  });

  сказать('\nИгр в порядке ' + итог.вПорядке + ', в долгу ' + итог.вДолгу);
  return итог;
}

