/** Копия страниц корня и папки js/ во временной папке. */
function копияПроекта(имя) {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'билет-бота-' + имя + '-'));
  fs.readdirSync(ПРОЕКТ).filter(function (ф) { return /\.html$/.test(ф); }).forEach(function (ф) {
    fs.copyFileSync(path.join(ПРОЕКТ, ф), path.join(папка, ф));
  });
  require('./пути-проекта.js').скопироватьКод(ПРОЕКТ, папка, 'js');
  return папка;
}

/** Заменить строку «старое» на «новое» — ровно одно вхождение в файле,
 * иначе порча устарела (файл переписали) и проверка обязана сказать
 * об этом внятно, а не молча проверить старый текст. */
function заменитьРовноОдин(файл, старое, новое) {
  const текст = fs.readFileSync(файл, 'utf8');
  const части = текст.split(старое);
  if (части.length !== 2) {
    throw new Error('приём порчи устарел: «' + старое + '» в ' + файл + ' встречается ' + (части.length - 1) + ' раз(а) вместо одного — поправьте проверку тем же коммитом');
  }
  fs.writeFileSync(файл, части.join(новое), 'utf8');
}

/** Убрать <script src="js/имя…"> со страницы независимо от ?v= — ровно
 * одно вхождение, иначе порча устарела. */
function убратьПодключение(файл, скрипт) {
  const текст = fs.readFileSync(файл, 'utf8');
  const образец = new RegExp('<script[^>]*\\ssrc="' + экранировать(скрипт) + '(?:\\?[^"]*)?"[^>]*></script>');
  const совпадения = текст.match(new RegExp(образец.source, 'g')) || [];
  if (совпадения.length !== 1) {
    throw new Error('приём порчи устарел: подключение ' + скрипт + ' в ' + файл + ' встречается ' + совпадения.length + ' раз(а) вместо одного');
  }
  fs.writeFileSync(файл, текст.replace(образец, ''), 'utf8');
}

/** Заменить «старое» на «новое», но только внутри окна текста сразу
 * после первого появления «якорь» — чтобы не задеть другую запись
 * реестра с точно такой же строкой способОчков. */
function заменитьВОкнеПослеЯкоря(файл, якорь, старое, новое, длинаОкна) {
  const текст = fs.readFileSync(файл, 'utf8');
  const где = текст.indexOf(якорь);
  if (где === -1) throw new Error('приём порчи устарел: в ' + файл + ' нет «' + якорь + '»');
  const окно = текст.slice(где, где + (длинаОкна || 400));
  const позиция = окно.indexOf(старое);
  if (позиция === -1) throw new Error('приём порчи устарел: рядом с «' + якорь + '» в ' + файл + ' нет «' + старое + '»');
  const абсолют = где + позиция;
  fs.writeFileSync(файл, текст.slice(0, абсолют) + новое + текст.slice(абсолют + старое.length), 'utf8');
}

