'use strict';

/* =====================================================================
   Проверка server/турниры.js, этап Э1: расписание по Москве, запись,
   хранение в файле.

   Запуск:
     node tests/турниры-расписание.js
       сама себя запускает дочерним процессом дважды — с поясом машины
       Asia/Tokyo и с UTC; в каждом гоняет все проверки и сверяет
       «отпечаток» расписания: он обязан быть одинаковым.
     node tests/турниры-расписание.js --сломать <путь к копии вне проекта>
       ломающий запуск: кладёт по этому пути КОПИЮ модуля, считающую время
       по местному поясу (get* вместо getUTC*), и требует, чтобы проверка
       на ней покраснела. Настоящий файл не трогается. Код выхода 1 =
       проверка покраснела (так и нужно); 0 = не покраснела (беда).
     Служебное: --внутри <модуль> <база> — один прогон в одном поясе.

   Данные пишутся в папку во временной папке, боевые не трогаются.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const КОРЕНЬ = path.resolve(__dirname, '..');
const НАСТОЯЩИЙ_МОДУЛЬ = path.join(КОРЕНЬ, 'server', 'турниры.js');
const ЧАС = 60 * 60 * 1000;
const СУТКИ = 24 * ЧАС;

/* ---------------------------------------------------------------------
   Прогон внутри одного процесса (пояс задаёт родитель через TZ)
   --------------------------------------------------------------------- */
function прогонВнутри(путьМодуля, базаМс) {
  let проверок = 0;
  let провалов = 0;
  function проверить(условие, что) {
    проверок++;
    if (!условие) {
      провалов++;
      console.log('  ПРОВАЛ: ' + что);
    }
  }

  /* Московское время «день+смещение, ч:м:с» в миллисекундах UTC.
     База — московская полночь выбранного дня (в мс UTC). Москва = UTC+3. */
  function мск(дней, ч, м, с, мс) {
    return базаМс + дней * СУТКИ + ((ч * 60 + м) * 60 + (с || 0)) * 1000 + (мс || 0);
  }

  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'турниры-э1-'));
  const ключ = require.resolve(путьМодуля);
  function свежийМодуль() {
    delete require.cache[ключ];
    return require(путьМодуля);
  }

  const T = свежийМодуль();
  T.включитьЗапись(папка);

  const д = new Date(базаМс + 3 * ЧАС);
  const деньГГГГ = д.getUTCFullYear() + '-' + String(д.getUTCMonth() + 1).padStart(2, '0') + '-' + String(д.getUTCDate()).padStart(2, '0');
  const завтра = new Date(базаМс + СУТКИ + 3 * ЧАС);
  const завтраГГГГ = завтра.getUTCFullYear() + '-' + String(завтра.getUTCMonth() + 1).padStart(2, '0') + '-' + String(завтра.getUTCDate()).padStart(2, '0');

  /* 1. Начало дня: 20:00 МСК = 17:00 UTC, при любом поясе машины. */
  const в20 = T.турнирДня(мск(0, 20, 0, 0));
  проверить(в20.началоМс === базаМс + 20 * ЧАС, 'начало 20:00 МСК (' + new Date(в20.началоМс).toISOString() + ')');
  проверить(new Date(в20.началоМс).toISOString().slice(11, 16) === '17:00', 'начало = 17:00 по UTC');
  проверить(в20.конецМс - в20.началоМс === 30 * 60 * 1000, 'длится 30 минут');
  проверить(в20.ид === 'дурак-' + деньГГГГ, 'ид дня: ' + в20.ид + ' ждали дурак-' + деньГГГГ);
  проверить(в20.игра === 'дурак', 'игра — дурак');

  /* 2. Граница суток по Москве: 23:59 МСК (20:59 UTC) ещё сегодня,
        00:00 МСК (21:00 UTC) уже завтра. */
  const впоследнююМинуту = T.турнирДня(мск(0, 23, 59, 0));
  const впоследнююМс = T.турнирДня(мск(0, 23, 59, 59, 999));
  const впервуюМс = T.турнирДня(мск(1, 0, 0, 0));
  проверить(new Date(мск(0, 23, 59, 0)).toISOString().slice(11, 16) === '20:59', 'самопроверка: 23:59 МСК = 20:59 UTC');
  проверить(new Date(мск(1, 0, 0, 0)).toISOString().slice(11, 16) === '21:00', 'самопроверка: 00:00 МСК = 21:00 UTC');
  проверить(впоследнююМинуту.ид === 'дурак-' + деньГГГГ, '23:59 МСК — ещё тот же день: ' + впоследнююМинуту.ид);
  проверить(впоследнююМс.ид === 'дурак-' + деньГГГГ, '23:59:59.999 МСК — ещё тот же день');
  проверить(впервуюМс.ид === 'дурак-' + завтраГГГГ, '00:00 МСК — уже новый день: ' + впервуюМс.ид);
  проверить(впоследнююМинуту.состояние === 'окончен', 'в 23:59 сегодняшний турнир окончен');
  проверить(впервуюМс.состояние === 'запись', 'в 00:00 новый турнир — запись уже открыта (весь день)');
  проверить(впервуюМс.началоМс === в20.началоМс + СУТКИ, 'завтрашнее начало ровно на сутки позже');

  /* 3. Состояния на границах. */
  const ожидание = [
    [0, 0, 0, 'запись'], [18, 59, 0, 'запись'], [19, 59, 0, 'запись'],
    [20, 0, 0, 'идёт'], [20, 29, 59, 'идёт'], [20, 30, 0, 'доигрыш'],
    [20, 39, 59, 'доигрыш'], [20, 40, 0, 'окончен']
  ];
  for (const [ч, м, с, ждём] of ожидание) {
    const получили = T.турнирДня(мск(0, ч, м, с)).состояние;
    проверить(получили === ждём, ч + ':' + м + ':' + с + ' МСК — ждали «' + ждём + '», получили «' + получили + '»');
  }

  /* 4. Запись открыта весь день до 20:25; с 20:25 и в доигрыше — отказ словами. */
  const поздно2025 = T.записать(111, 'Поздно', мск(0, 20, 25, 0));
  проверить(поздно2025.ок === false && typeof поздно2025.почему === 'string' && поздно2025.почему.length > 5, 'в 20:25:00 запись закрыта, отказ словами');
  проверить(T.участники('дурак-' + деньГГГГ).length === 0, 'после отказа участников нет');
  проверить(T.записать(112, 'Ночной', мск(0, 0, 0, 0)).ок === true && T.отписать(112, мск(0, 0, 1, 0)).ок === true, 'в полночь запись уже открыта (и снимается)');
  const вЗапись = T.записать(222, '  Аня  ', мск(0, 19, 0, 0));
  проверить(вЗапись.ок === true, 'в 19:00 запись открыта');
  const вИдёт = T.записать(333, 'Боря', мск(0, 20, 24, 59));
  проверить(вИдёт.ок === true, 'в 20:24:59 записаться ещё можно');
  const поздно = T.записать(444, 'Поздно', мск(0, 20, 30, 0));
  проверить(поздно.ок === false && typeof поздно.почему === 'string' && поздно.почему.length > 5, 'после конца — отказ словами');

  /* 5. Повторная запись не задваивает. */
  const ещёРаз = T.записать(222, 'Аня', мск(0, 19, 30, 0));
  проверить(ещёРаз.ок === true, 'повторная запись — не ошибка');
  const идДня = 'дурак-' + деньГГГГ;
  const список = T.участники(идДня);
  проверить(список.length === 2, 'участников двое, не трое (' + список.length + ')');
  проверить(список.some(function (у) { return у.номер === 222 && у.имя === 'Аня'; }), 'имя обрезано от пробелов');
  проверить(T.видДляВсех(мск(0, 20, 5, 0)).записалось === 2, 'видДляВсех: записалось 2');

  /* 6. Отписка: до начала можно, после — нет. */
  проверить(T.записать(555, 'Витя', мск(0, 19, 5, 0)).ок === true, 'Витя записался');
  проверить(T.отписать(555, мск(0, 19, 10, 0)).ок === true, 'Витя отписался до начала');
  проверить(T.отписать(333, мск(0, 20, 12, 0)).ок === false, 'во время турнира отписаться нельзя');
  проверить(T.участники(идДня).length === 2, 'после отписки снова двое');

  /* 7. Личина записаться не может. */
  T.подключить({ этоЛичина: function (номер) { return номер === 999; } });
  const личина = T.записать(999, 'Личина', мск(0, 19, 30, 0));
  проверить(личина.ок === false, 'личина — отказ');
  проверить(!T.участники(идДня).some(function (у) { return у.номер === 999; }), 'личины в списке нет');
  проверить(T.записать(666, 'Живой', мск(0, 19, 31, 0)).ок === true, 'не личина записывается и после подключения');
  проверить(T.записать(-5, 'Минус', мск(0, 19, 31, 0)).ок === false, 'негодный номер — отказ');

  /* 8. Вид для всех: одни числа и состояние, ни номеров, ни имён. */
  const вид = T.видДляВсех(мск(0, 20, 5, 0));
  const текстВида = JSON.stringify(вид);
  проверить(вид.записалось === 3, 'видДляВсех: записалось 3 (222, 333, 666) — ' + вид.записалось);
  проверить(!/222|333|666|999/.test(текстВида.replace(/"(началоМс|конецМс)":\d+/g, '')), 'в видДляВсех нет номеров Telegram');
  проверить(текстВида.indexOf('Аня') === -1 && текстВида.indexOf('Боря') === -1, 'в видДляВсех нет имён');
  проверить(Object.keys(вид).sort().join(',') === 'записалось,записан,игра,ид,конецМс,началоМс,состояние,таблица', 'в видДляВсех ровно нужные поля: ' + Object.keys(вид).join(','));

  /* 9. Перезапуск: участники возвращаются с диска. */
  T.дописать();
  проверить(fs.existsSync(path.join(папка, 'турниры.json')), 'файл турниры.json появился на диске');
  проверить(!fs.existsSync(path.join(папка, 'турниры.json.пишем')), 'временного файла не осталось');
  const после = свежийМодуль();
  после.включитьЗапись(папка);
  const вернулись = после.участники(идДня).map(function (у) { return у.номер; }).sort().join(',');
  проверить(вернулись === '222,333,666', 'после перезапуска участники с диска: «' + вернулись + '»');
  проверить(после.видДляВсех(мск(0, 20, 5, 0)).записалось === 3, 'после перезапуска видДляВсех считает троих');

  /* 10. Битый файл откладывается в .битый, а не роняет модуль. */
  fs.writeFileSync(path.join(папка, 'турниры.json'), '{не json', 'utf8');
  const послеБеды = свежийМодуль();
  послеБеды.включитьЗапись(папка);
  проверить(послеБеды.участники(идДня).length === 0, 'битый файл — начали с чистого листа');
  проверить(fs.existsSync(path.join(папка, 'турниры.json.битый')), 'битый файл отложен в .битый');

  /* Отпечаток расписания: должен совпасть в любом поясе. */
  const моменты = [
    [0, 0, 0, 0], [0, 18, 59, 59], [0, 19, 0, 0], [0, 20, 0, 0], [0, 20, 29, 59],
    [0, 20, 30, 0], [0, 23, 59, 59], [1, 0, 0, 0], [1, 12, 0, 0]
  ];
  const отпечаток = моменты.map(function (м) {
    const т = T.турнирДня(мск(м[0], м[1], м[2], м[3]));
    return [т.ид, т.началоМс, т.конецМс, т.состояние];
  });

  for (const имя of ['турниры.json', 'турниры.json.битый', 'турниры.json.пишем']) {
    try { fs.unlinkSync(path.join(папка, имя)); } catch (_) { /* не было — не беда */ }
  }
  try { fs.rmdirSync(папка); } catch (_) { /* осталась — лежит во временной папке */ }

  /* Сколько минут пояс машины отличается от UTC: родитель сверит, что в двух прогонах оно РАЗНОЕ. */
  const смещениеПояса = new Date(базаМс).getTimezoneOffset();
  console.log('  пояс процесса: getTimezoneOffset() = ' + смещениеПояса);
  return { проверок: проверок, провалов: провалов, отпечаток: отпечаток, смещениеПояса: смещениеПояса };
}

/* ---------------------------------------------------------------------
   Родитель: запуск в двух поясах и сверка
   --------------------------------------------------------------------- */
function запуститьВПоясе(пояс, путьМодуля, базаМс) {
  const итог = spawnSync(process.execPath, [__filename, '--внутри', путьМодуля, String(базаМс)], {
    env: Object.assign({}, process.env, { TZ: пояс }),
    encoding: 'utf8'
  });
  const строки = (итог.stdout || '').split('\n');
  const последняя = строки.filter(function (с) { return с.indexOf('ИТОГ ') === 0; }).pop();
  let разбор = null;
  try { разбор = last(последняя); } catch (_) { разбор = null; }
  return { пояс: пояс, вывод: итог.stdout || '', ошибки: итог.stderr || '', итог: разбор };
}
function last(строка) { return JSON.parse(строка.slice(5)); }

/** Московская полночь сегодняшнего дня, мс UTC (считаем независимо от модуля). */
function базаСегодня() {
  const д = new Date(Date.now() + 3 * ЧАС);
  return Date.UTC(д.getUTCFullYear(), д.getUTCMonth(), д.getUTCDate()) - 3 * ЧАС;
}

function главная() {
  const аргументы = process.argv.slice(2);

  if (аргументы[0] === '--внутри') {
    const результат = прогонВнутри(аргументы[1], Number(аргументы[2]));
    console.log('ИТОГ ' + JSON.stringify(результат));
    return;
  }

  let путьМодуля = НАСТОЯЩИЙ_МОДУЛЬ;
  const ломаем = аргументы[0] === '--сломать';
  if (ломаем) {
    const цель = path.resolve(аргументы[1] || '');
    if (!аргументы[1] || цель.toLowerCase().startsWith(КОРЕНЬ.toLowerCase() + path.sep)) {
      console.log('Нужен путь к копии ВНЕ проекта (например, в %TEMP%).');
      process.exit(2);
    }
    let текст = fs.readFileSync(НАСТОЯЩИЙ_МОДУЛЬ, 'utf8');
    const заменено = (текст.match(/getUTC/g) || []).length;
    if (заменено === 0) {
      console.log('Ломать нечего: в модуле нет getUTC — проверка устарела.');
      process.exit(2);
    }
    текст = текст.replace(/getUTC/g, 'get');
    текст = текст.replace("require('./папка-данных.js')", 'require(' + JSON.stringify(path.join(КОРЕНЬ, 'server', 'папка-данных.js')) + ')');
    fs.writeFileSync(цель, текст, 'utf8');
    путьМодуля = цель;
    console.log('Ломающий запуск: копия ' + цель + ', подменено getUTC → get: ' + заменено);
  }

  const база = базаСегодня();
  const прогоны = ['Asia/Tokyo', 'UTC'].map(function (пояс) {
    return запуститьВПоясе(пояс, путьМодуля, база);
  });

  let провалов = 0;
  let проверок = 0;
  for (const п of прогоны) {
    if (!п.итог) {
      провалов++;
      console.log('[' + п.пояс + '] прогон не дал итога. Вывод:\n' + п.вывод + п.ошибки);
      continue;
    }
    проверок += п.итог.проверок;
    провалов += п.итог.провалов;
    console.log('[' + п.пояс + '] проверок ' + п.итог.проверок + ', провалов ' + п.итог.провалов + ', getTimezoneOffset() = ' + п.итог.смещениеПояса);
    if (п.итог.провалов > 0) console.log(п.вывод.split('\n').filter(function (с) { return с.indexOf('ИТОГ ') !== 0; }).join('\n'));
  }
  const обаИтога = прогоны.every(function (п) { return п.итог; });
  if (обаИтога) {
    проверок++;
    const одинаково = JSON.stringify(прогоны[0].итог.отпечаток) === JSON.stringify(прогоны[1].итог.отпечаток);
    if (!одинаково) {
      провалов++;
      console.log('  ПРОВАЛ: расписание в Asia/Tokyo и в UTC разное — модуль зависит от пояса машины');
    }
    /* Если пояс не поменялся (TZ не подействовал), сверка поясов — пустышка: краснеем. */
    проверок++;
    if (прогоны[0].итог.смещениеПояса === прогоны[1].итог.смещениеПояса) {
      провалов++;
      console.log('  ПРОВАЛ: getTimezoneOffset() одинаков в обоих прогонах (' + прогоны[0].итог.смещениеПояса + ') — пояса не различались, проверка ничего не доказывает');
    }
    /* Ноль найденного — провал: пустой отпечаток ничего не доказывает. */
    проверок++;
    if (!(прогоны[0].итог.отпечаток.length > 0 && прогоны[0].итог.проверок > 30)) {
      провалов++;
      console.log('  ПРОВАЛ: проверок слишком мало — прогон ничего не нашёл');
    }
  }

  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
  if (провалов > 0) {
    console.log(ломаем ? 'КРАСНАЯ (ломающий запуск так и должен): проверка заметила порчу.' : 'КРАСНАЯ: есть провалы.');
    process.exit(1);
  }
  console.log(ломаем ? 'ЗЕЛЁНАЯ на сломанной копии — проверка слепая!' : 'ЗЕЛЁНАЯ: всё в порядке.');
}

главная();
