/** В --сломать вешает на страницу подмену /style-витрина.css испорченной копией из временной папки.
    Имя файла кириллическое — браузер шлёт его закодированным («%D0%B2…»), а playwright.route()
    со строкой/регуляркой сверяет закодированный вид (та же ловушка, что в tests/браузер-робот.js
    про «перехват запроса по русскому адресу»). Поэтому маршрут ставим ФУНКЦИЕЙ-ПРИМЕТОЙ, которая
    раскодирует адрес сама: playwright сам решает, вызывать ли обработчик, и на «не подошло» просто
    идёт смотреть более ранние маршруты/сеть — в отличие от перехватить() это НЕ катит следующим
    зарегистрированным маршрутам «continue()» и не отбирает у них шанс сработать, поэтому порядок
    регистрации относительно перехватить(…, /рейтинг…) ниже не важен. */
async function подключитьЛомающийCss(страница, путьКопии) {
  await страница.route((url) => {
    let адрес;
    try { адрес = decodeURIComponent(url.href); } catch (ошибка) { адрес = url.href; }
    return /\/style-витрина\.css(?:\?|$)/.test(адрес);
  }, async (маршрут) => {
    const тело = fs.readFileSync(путьКопии, 'utf8');
    await маршрут.fulfill({ status: 200, contentType: 'text/css; charset=utf-8', body: тело });
  });
}

/* ---------------------------------------------------------------------
   Число плиток в разметке — не зашитое число, а живой счёт по index.html.
   --------------------------------------------------------------------- */

function числоПлитокВРазметке() {
  const html = fs.readFileSync(path.join(КОРЕНЬ, 'index.html'), 'utf8');
  // Плитки — вперемешку <button> (готовые игры без своей страницы: нарды,
  // шахматы, дурак, шашки) и <a href="…"> (игры со своей страницей: домино,
  // морской бой, катан, деберц) — считаем оба тега.
  const совпадения = html.match(/<(?:a|button)\s[^>]*class="плитка-игры"[^>]*>/g) || [];
  return совпадения.length;
}

