const АДРЕС = '127.0.0.1';
let ПОРТ = 0;
const ТОКЕН = '7654321:VYDUMANNYY-TOKEN-DLYA-PROVERKI-lichiny';

let проверок = 0;
const провалы = [];
function проверить(условие, что) {
  проверок++;
  if (!условие) { провалы.push(что); console.log('  ПРОВАЛ: ' + что); }
}

function подписать(поля) {
  const строки = Object.keys(поля).map(function (к) { return к + '=' + поля[к]; }).sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(ТОКЕН).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}
function подпись(номер, имя) {
  const поля = {
    query_id: 'AAF' + номер,
    user: JSON.stringify({ id: номер, first_name: имя, username: 'igrok' + номер }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  const всё = Object.assign({}, поля, { hash: подписать(поля) });
  return Object.keys(всё).map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(всё[к]); }).join('&');
}

function спросить(путь, тело, терпениеМс) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    let конец = false;
    const запрос = http.request({
      host: АДРЕС, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (к) { текст += к; });
      ответ.on('end', function () {
        if (конец) return; конец = true; clearTimeout(сторож);
        let тело = {}; try { тело = JSON.parse(текст || '{}'); } catch (с) { /* пусто */ }
        готово({ код: ответ.statusCode, тело: тело });
      });
    });
    const сторож = терпениеМс ? setTimeout(function () {
      if (конец) return; конец = true; запрос.destroy(); готово({ код: 0, тело: {}, оборван: true });
    }, терпениеМс) : null;
    запрос.on('error', function (с) { if (!конец) { конец = true; беда(с); } });
    запрос.write(данные); запрос.end();
  });
}

function получить(путь) {
  return new Promise(function (готово, беда) {
    http.get({ host: АДРЕС, port: ПОРТ, path: encodeURI(путь) }, function (ответ) {
      const куски = [];
      ответ.on('data', function (к) { куски.push(к); });
      ответ.on('end', function () { готово({ код: ответ.statusCode, тип: ответ.headers['content-type'], байты: Buffer.concat(куски) }); });
    }).on('error', беда);
  });
}

async function встатьИДождаться(номер, имя, игра) {
  const встал = await спросить('/подбор', { initData: подпись(номер, имя), игра: игра, переводной: false });
  проверить(встал.тело.статус === 'ждёт', имя + ': встал в очередь (' + JSON.stringify(встал.тело) + ')');
  const ключ = встал.тело.ключОжидания;

  // 1) Раньше 8 секунд — никого.
  const рано = await спросить('/подбор-новости', { ключОжидания: ключ }, 1500);
  проверить(рано.оборван || рано.тело.изменилось === false, имя + ': раньше 8 с личины нет');

  // 2) Через 21 с — свели. Часы двигаем шагами по 4 с с опросом между ними:
  //    запись очереди без опроса дольше 15 с уходит (server/подбор.js).
  let поздно = null;
  for (let шаг = 0; шаг < 6; шаг++) {
    сдвиг += 4000;
    поздно = await спросить('/подбор-новости', { ключОжидания: ключ }, 1500);
    if (поздно.тело.статус === 'свели') break;
    проверить(шаг >= 1 || поздно.оборван || поздно.тело.изменилось === false, имя + ': на 4-й секунде ещё ждёт');
  }
  проверить(поздно.тело.статус === 'свели' && поздно.тело.код && поздно.тело.пропуск,
    имя + ': после 20 с опрос «свели» (' + JSON.stringify(поздно.тело) + ')');
  return поздно.тело;
}

async function проверитьВсё() {
  const стол = await встатьИДождаться(501, 'Аня', 'шашки');
  const найдено = комнаты.найтиИгрока(стол.код, стол.пропуск);
  проверить(Boolean(найдено), 'стол Ани найден');
  if (!найдено) return;
  const комната = найдено.комната;
  const местоАни = найдено.ктоЯ;
  const местоЛичины = Object.keys(комната.игроки).find(function (м) { return м !== местоАни; });
  const личинаМесто = комната.игроки[местоЛичины];

  проверить(комната.этап === 'игра', 'партия идёт (этап ' + комната.этап + ')');

  // 3) Внутри — бот с личиной.
  проверить(личинаМесто && личинаМесто.этоБот === true, 'за вторым местом — серверный бот');
  const номерЛичины = личинаМесто && личинаМесто.личина && личинаМесто.личина.номер;
  проверить(личины.этоЛичина(номерЛичины), 'у места номер личины');
  const личина = личины.личинаПоНомеру(номерЛичины);
  проверить(личина && личинаМесто.имя === личина.имя, 'имя места — имя личины («' + (личинаМесто && личинаМесто.имя) + '»)');
  проверить(!/^Бот/.test(личинаМесто.имя || ''), 'имя не начинается с «Бот»');
  проверить(комната.событие && комната.событие.что === 'вошёл', 'событие стола «вошёл» (было «' + (комната.событие && комната.событие.что) + '»)');

  // 4) Снаружи — человек.
  const вид = комнаты.показатьИгроку(комната, местоАни);
  const портрет = (вид.аватары || []).find(function (а) { return !а.этоЯ; });
  проверить(Boolean(портрет), 'в виде есть портрет соперника');
  проверить(портрет && портрет.этоБот === false, 'снаружи соперник — не бот');
  проверить(портрет && typeof портрет.фото === 'string' && портрет.фото.length === 24, 'у соперника есть ключ фото');
  if (портрет && портрет.фото) {
    const фото = await получить('/фото/' + портрет.фото);
    if (личины.естьФото(номерЛичины)) {
      проверить(фото.код === 200 && /svg/.test(фото.тип || ''), 'фото личины отдаётся картинкой (' + фото.код + ' ' + фото.тип + ')');
    } else {
      проверить(фото.код === 404, 'у личины без фото — 404, как у человека без фото');
    }
  }
  const строкаМест = JSON.stringify(вид);
  проверить(строкаМест.indexOf('"этоБот":true') === -1, 'в виде для игрока нигде нет «этоБот: true»');

  // 5) Рейтинг.
  const застолье = комнаты.застольеДляРейтинга(комната);
  const вРейтинге = застолье.find(function (з) { return з.номер === номерЛичины; });
  проверить(Boolean(вРейтинге), 'личина в застолье рейтинга со своим номером');
  проверить(вРейтинге && вРейтинге.этоБот === false, 'для рейтинга личина — не бот');

  // 5б) «В друзья» у личины — как у живого соседа: ключ есть, заявка «ожидает».
  const соседи = await спросить('/друзья-за-столом', { initData: подпись(501, 'Аня'), код: стол.код, пропуск: стол.пропуск });
  const соседЛичина = (соседи.тело.места || [])[0];
  проверить(соседЛичина && соседЛичина.ключ && соседЛичина.статус === 'нет', 'у соседа-личины есть кнопка «В друзья» (' + JSON.stringify(соседи.тело) + ')');
  if (соседЛичина && соседЛичина.ключ) {
    const зов = await спросить('/друзья-позвать', { initData: подпись(501, 'Аня'), ключ: соседЛичина.ключ });
    проверить(зов.тело.ок === true && зов.тело.статус === 'ожидает', 'заявка личине отправлена, «ожидает»');
    const снова = await спросить('/друзья-за-столом', { initData: подпись(501, 'Аня'), код: стол.код, пропуск: стол.пропуск });
    проверить(снова.тело.места && снова.тело.места[0].статус === 'позван', 'после заявки сосед-личина «позван»');
  }

  // 6) Второй ждущий — другая личина.
  const стол2 = await встатьИДождаться(502, 'Боря', 'шашки');
  const найдено2 = комнаты.найтиИгрока(стол2.код, стол2.пропуск);
  const другое = найдено2 && Object.keys(найдено2.комната.игроки).find(function (м) { return м !== найдено2.ктоЯ; });
  const номер2 = другое && найдено2.комната.игроки[другое].личина && найдено2.комната.игроки[другое].личина.номер;
  проверить(личины.этоЛичина(номер2) && номер2 !== номерЛичины, 'у Бори другая личина');

  // 7) Кнопка «Играть с ботом» — обычный бот.
  const встал = await спросить('/подбор', { initData: подпись(503, 'Вера'), игра: 'шашки', переводной: false });
  const сБотом = await спросить('/подбор-с-ботом', { initData: подпись(503, 'Вера'), ключОжидания: встал.тело.ключОжидания });
  const найдено3 = сБотом.тело.код ? комнаты.найтиИгрока(сБотом.тело.код, сБотом.тело.пропуск) : null;
  const бот3 = найдено3 && Object.keys(найдено3.комната.игроки).map(function (м) { return найдено3.комната.игроки[м]; }).find(function (и) { return и.этоБот; });
  проверить(бот3 && !бот3.личина, 'по кнопке садится обычный бот, не личина');

  // 8) Темп.
  const паузы = [];
  for (let i = 0; i < 40; i++) паузы.push(личины.паузаХода('шахматы', 700, 0));
  проверить(Math.min.apply(null, паузы) >= 900 && Math.max.apply(null, паузы) <= 22000, 'паузы в пределах 0,9–22 с');
  проверить(new Set(паузы).size > 30, 'паузы разные от хода к ходу');
  проверить(личины.паузаХода('шашки', 700, 10) <= 6000, 'при лимите 10 с на ход пауза не больше 6 с');
}

(async function () {
  console.log('=== Личины в подборе ===');
  сервера.оснасткаДляПроверки(ТОКЕН, function () { return { ok: true }; });
  const сервер = сервера.создатьСервер();
  await new Promise(function (готово, беда) { сервер.once('error', беда); сервер.listen(0, АДРЕС, готово); });
  ПОРТ = сервер.address().port;
  let сбой = null;
  try { await проверитьВсё(); } catch (б) { сбой = б; }
  сервер.close();
  сервера.оснасткаДляПроверки();
  if (сбой) { console.log('ПРОВЕРКА ОБОРВАЛАСЬ: ' + сбой.stack); process.exit(1); }
  console.log('\nпроверок: ' + проверок + ', провалов: ' + провалы.length);
  process.exit(провалы.length ? 1 : 0);
})();
