/** Красные строки консоли — кроме отказа настоящему Telegram (сам приём подделки). */
function следитьЗаКонсолью(страница, красные, имя) {
  страница.on('pageerror', (о) => красные.push('падение у ' + имя + ': ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const текст = м.text();
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js|telegram\.org/.test(текст + ' ' + откуда)) return;
    красные.push('консоль у ' + имя + ': ' + текст + (откуда ? ' (' + откуда + ')' : ''));
  });
}

