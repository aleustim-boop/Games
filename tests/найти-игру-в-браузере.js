function создатьИзвлекатель(текст, имяФайла) {
  return function извлечь(регулярка, откуда) {
    const найдено = текст.match(регулярка);
    if (!найдено) throw new Error('не нашёл в ' + имяФайла + ': ' + откуда);
    return найдено[1];
  };
}

