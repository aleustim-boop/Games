// Проверка общих классов «стекла» в style.css (этап П1 «Захвата»).
// Запуск: node tests/стекло-классы.js [--css <путь к css>] [--сломать]
// Флаг --сломать: проверка сама копирует style.css во временную папку (os.tmpdir())
// и прогоняет себя на порченых копиях: blur(30px) в одном классе; убран один
// -webkit-backdrop-filter; backdrop-filter на .экран; убран background из правила
// @supports not; убран background из правила .стекло-без-размытия. Каждая порча
// обязана дать провал; если хоть одна прошла зелёной — выход с кодом 1.
// Настоящий style.css не трогается никогда.
// Без браузера, без библиотек. Ничего не найдено = провал, а не пропуск.
'use strict';
const fs = require('fs');
const path = require('path');

const КЛАССЫ = ['стекло-панель', 'стекло-капсула', 'стекло-кнопка-круг', 'стекло-акцент', 'стекло-полоса'];
const ПРЕДЕЛ_РАЗМЫТИЯ = 20;
const ПЕРЕКЛЮЧАТЕЛЬ = 'стекло-без-размытия';

// ---- путь к css ----
let путь = path.join(__dirname, '..', 'общее/css/style.css');
const ай = process.argv.indexOf('--css');
if (ай >= 0) {
  if (!process.argv[ай + 1]) { console.log('Не указан путь после --css'); process.exit(2); }
  путь = path.resolve(process.argv[ай + 1]);
}
let текст;
try { текст = fs.readFileSync(путь, 'utf8'); }
catch (e) { console.log('Не удалось прочитать css: ' + путь); console.log('Итого проверок: 1, провалов: 1'); process.exit(1); }
текст = текст.replace(/\/\*[\s\S]*?\*\//g, '');

// ---- ломающий запуск: порченые копии во временной папке ----
if (process.argv.includes('--сломать')) {
  const os = require('os');
  const { spawnSync } = require('child_process');
  const исходный = fs.readFileSync(путь, 'utf8');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'стекло-порча-'));
  const после = (с, метка, ф) => { const и = с.indexOf(метка); return и < 0 ? null : с.slice(0, и) + ф(с.slice(и)); };
  const порчи = [
    ['blur(30px) в одном классе', с => после(с, 'backdrop-filter: blur(16px)', х => х.replace('blur(16px)', 'blur(30px)'))],
    ['убран один -webkit-backdrop-filter', с => после(с, '-webkit-backdrop-filter: blur(12px)', х => х.replace('-webkit-backdrop-filter: blur(12px)', ''))],
    ['backdrop-filter на .экран', с => с + '\n.экран { backdrop-filter: blur(4px); }\n'],
    ['убран background из правила @supports not', с => после(с, '@supports not (backdrop-filter: blur(1px))', х => х.replace('background:', 'xbackground:'))],
    ['убран background из правила .стекло-без-размытия', с => после(с, '.стекло-без-размытия .стекло-акцент', х => х.replace('background:', 'xbackground:'))],
  ];
  const запуск = п => spawnSync(process.execPath, [__filename, '--css', п], { encoding: 'utf8' });
  let плохих = 0, всего = 0;
  const чистая = path.join(папка, 'чистая.css');
  fs.writeFileSync(чистая, исходный);
  const р0 = запуск(чистая); всего++;
  console.log((р0.status === 0 ? 'ЗЕЛЕНО  ' : 'КРАСНОЕ ') + 'непорченая копия проходит зелёной (иначе порча ничего не доказывает)');
  if (р0.status !== 0) плохих++;
  порчи.forEach((п, н) => {
    всего++;
    const сп = п[1](исходный);
    if (сп === null || сп === исходный) { плохих++; console.log('КРАСНОЕ порча «' + п[0] + '» не применилась — в css нет места для порчи'); return; }
    const ф = path.join(папка, 'порча-' + (н + 1) + '.css');
    fs.writeFileSync(ф, сп);
    const р = запуск(ф);
    const упала = р.status === 1 && /Итого проверок: \d+, провалов: [1-9]/.test(р.stdout);
    if (!упала) плохих++;
    console.log((упала ? 'ЗЕЛЕНО  ' : 'КРАСНОЕ ') + 'порча «' + п[0] + '» дала провал' + (упала ? '' : ' — ПРОВЕРКА НЕ ПОКРАСНЕЛА'));
  });
  console.log('Итого проверок: ' + всего + ', провалов: ' + плохих);
  process.exit(плохих ? 1 : 0);
}

// ---- разбор css в плоский список правил: {контекст, селекторы[], тело} ----
function разобрать(s, контекст, выход) {
  let поз = 0;
  while (поз < s.length) {
    const скобка = s.indexOf('{', поз);
    if (скобка < 0) break;
    let голова = s.slice(поз, скобка);
    const тч = голова.lastIndexOf(';');
    if (тч >= 0) голова = голова.slice(тч + 1);
    голова = голова.trim();
    // ищем парную закрывающую
    let глубина = 1, i = скобка + 1;
    while (i < s.length && глубина > 0) {
      if (s[i] === '{') глубина++;
      else if (s[i] === '}') глубина--;
      i++;
    }
    const тело = s.slice(скобка + 1, i - 1);
    if (/^@(supports|media|layer)/i.test(голова)) {
      разобрать(тело, контекст.concat(голова.replace(/\s+/g, ' ')), выход);
    } else if (голова.startsWith('@')) {
      // @keyframes, @font-face и т.п. — не селекторы, пропускаем
    } else {
      выход.push({ контекст, селекторы: голова.split(',').map(x => x.replace(/\s+/g, ' ').trim()).filter(Boolean), тело });
    }
    поз = i;
  }
  return выход;
}
const правила = разобрать(текст, [], []);

// ---- помощники ----
const БУКВА = 'A-Za-z0-9_\\-а-яёА-ЯЁ';
function содержитКласс(селектор, имя) {
  return new RegExp('\\.' + имя + '(?![' + БУКВА + '])').test(селектор);
}
function естьУзел(селектор, узел) { // '.экран' или '#приложение' как целое имя
  const эк = узел.replace(/[.#]/g, c => '\\' + c);
  return new RegExp(эк + '(?![' + БУКВА + '])').test(селектор);
}
const вСапортсНот = п => п.контекст.some(к => /^@supports\s+not\s*\(\s*(-webkit-)?backdrop-filter\s*:\s*blur\(\s*1px\s*\)\s*\)/i.test(к));
const БЛЮР = /(^|[;\s])(-webkit-)?backdrop-filter\s*:\s*([^;}]*)/gi;
function размытия(тело) { // [{префикс, значение}]
  const р = []; let м; БЛЮР.lastIndex = 0;
  while ((м = БЛЮР.exec(тело))) р.push({ веб: !!м[2], значение: м[3].trim() });
  return р;
}
const естьФон = тело => /(^|[;\s])background\s*:/i.test(тело);
const естьРазмытие = тело => размытия(тело).some(р => !/^none\b/i.test(р.значение));

// ---- проверки ----
const итог = [];
function проверка(название, ок, подробность) {
  итог.push(ок);
  console.log((ок ? 'ЗЕЛЕНО  ' : 'КРАСНОЕ ') + название + (ок || !подробность ? '' : ' — ' + подробность));
}

console.log('Файл: ' + путь + ' (правил разобрано: ' + правила.length + ')');
проверка('css разобран, правила найдены', правила.length > 0, 'ни одного правила');

// 1. классы как селекторы
for (const к of КЛАССЫ) {
  const н = правила.filter(п => п.селекторы.some(с => содержитКласс(с, к))).length;
  проверка('класс .' + к + ' есть как селектор', н > 0, 'не найден ни в одном правиле');
}

// основные правила класса: не в @supports not и без переключателя
const основное = (п, к) => !вСапортсНот(п) && п.селекторы.some(с => содержитКласс(с, к) && !содержитКласс(с, ПЕРЕКЛЮЧАТЕЛЬ));

// 2. размытие <= 20 px
for (const к of КЛАССЫ) {
  const своих = правила.filter(п => основное(п, к));
  const все = [];
  своих.forEach(п => размытия(п.тело).forEach(р => все.push(р)));
  const обычных = все.filter(р => !р.веб);
  const веб = все.filter(р => р.веб);
  const числа = [];
  let плохо = '';
  for (const р of все) {
    const м = /blur\(\s*([0-9.]+)\s*(px)?\s*\)/i.exec(р.значение);
    if (!м) { плохо = 'не разобрать значение «' + р.значение + '»'; continue; }
    числа.push(parseFloat(м[1]));
  }
  let ок = true, почему = '';
  if (!обычных.length) { ок = false; почему = 'нет backdrop-filter у класса'; }
  else if (!веб.length) { ок = false; почему = 'нет -webkit-backdrop-filter у класса'; }
  else if (плохо) { ок = false; почему = плохо; }
  else if (числа.some(ч => ч > ПРЕДЕЛ_РАЗМЫТИЯ)) { ок = false; почему = 'размытие ' + Math.max(...числа) + ' px больше ' + ПРЕДЕЛ_РАЗМЫТИЯ; }
  проверка('размытие у .' + к + ' не больше ' + ПРЕДЕЛ_РАЗМЫТИЯ + ' px (backdrop-filter и -webkit-)', ок, почему);
}

// 3. запасной вид: @supports not и переключатель, без backdrop-filter
for (const к of КЛАССЫ) {
  const вСап = правила.filter(п => вСапортсНот(п) && п.селекторы.some(с => содержитКласс(с, к)));
  проверка('у .' + к + ' есть правило в @supports not (backdrop-filter…)', вСап.length > 0, 'правила нет');
  проверка('у .' + к + ' в @supports not нет backdrop-filter', вСап.length > 0 && !вСап.some(п => /backdrop-filter/i.test(п.тело)), вСап.length ? 'в правиле внутри @supports not не должно быть слова backdrop-filter' : 'правила нет');
  проверка('у .' + к + ' в @supports not есть background', вСап.length > 0 && вСап.every(п => естьФон(п.тело)), 'запасное правило без background — панель станет прозрачной');
  const пер = правила.filter(п => п.селекторы.some(с => содержитКласс(с, ПЕРЕКЛЮЧАТЕЛЬ) && содержитКласс(с, к)));
  проверка('у .' + к + ' есть правило под .' + ПЕРЕКЛЮЧАТЕЛЬ, пер.length > 0, 'правила «.' + ПЕРЕКЛЮЧАТЕЛЬ + ' .' + к + '» нет');
  проверка('у .' + к + ' под .' + ПЕРЕКЛЮЧАТЕЛЬ + ' есть background', пер.length > 0 && пер.every(п => естьФон(п.тело)), 'запасное правило без background — панель станет прозрачной');
  проверка('у .' + к + ' под .' + ПЕРЕКЛЮЧАТЕЛЬ + ' нет backdrop-filter', пер.length > 0 && !пер.some(п => естьРазмытие(п.тело)), пер.length ? 'размытие осталось в запасном правиле' : 'правила нет');
}

// 4. размытие не у #приложение и не у .экран (во всём файле)
{
  const плохие = [];
  for (const п of правила) {
    if (!естьРазмытие(п.тело)) continue;
    for (const с of п.селекторы) {
      if (естьУзел(с, '#приложение') || естьУзел(с, '.экран')) плохие.push(с);
    }
  }
  проверка('ни у #приложение, ни у .экран нет backdrop-filter', плохие.length === 0, 'размытие у: ' + плохие.join(' | '));
  const сРазмытием = правила.filter(п => естьРазмытие(п.тело)).length;
  проверка('в файле вообще есть правила с backdrop-filter (иначе проверка пустая)', сРазмытием > 0, 'ни одного');
}

const провалов = итог.filter(x => !x).length;
console.log('Итого проверок: ' + итог.length + ', провалов: ' + провалов);
process.exit(провалов ? 1 : 0);
