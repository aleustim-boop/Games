/** Узел страницы: классы, текст, обработчики нажатия, вставка соседа. */
function сделатьУзел(id, страница) {
  const классы = new Set();
  const обработчики = [];
  const узел = {
    id: id || '', value: '', textContent: '', type: '', disabled: false,
    style: {}, dataset: {},
    classList: {
      toggle: function (имя, есть) {
        const надо = есть === undefined ? !классы.has(имя) : Boolean(есть);
        if (надо) классы.add(имя); else классы.delete(имя);
        return надо;
      },
      add: function (имя) { классы.add(имя); },
      remove: function (имя) { классы.delete(имя); },
      contains: function (имя) { return классы.has(имя); }
    },
    get className() { return Array.from(классы).join(' '); },
    set className(что) {
      классы.clear();
      String(что || '').split(/\s+/).filter(Boolean).forEach(function (к) { классы.add(к); });
    },
    addEventListener: function (вид, что) { if (вид === 'click') обработчики.push(что); },
    removeEventListener: function () {},
    нажать: function () { обработчики.forEach(function (о) { о({ preventDefault: function () {} }); }); },
    focus: function () {}, blur: function () {},
    setAttribute: function () {}, removeAttribute: function () {},
    querySelector: function () { return null; },
    querySelectorAll: function () { return []; },
    appendChild: function () {}, removeChild: function () {},
    insertAdjacentElement: function (где, сосед) {
      if (сосед && сосед.id) страница.узлы.set(сосед.id, сосед);
      страница.порядок.push(сосед && сосед.id);
      return сосед;
    }
  };
  return узел;
}

