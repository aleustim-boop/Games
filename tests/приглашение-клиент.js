async function раздел2() {
  console.log('\n2. Запасной путь: буфер и окно выбора чата');
  const с = await засестьЗаСтол({
    сервер: сервер({ подготовил: false }),
    поделиться: function (номер, колбэк) { колбэк(true); }
  });
  // Приглашение спрошено заранее, при показе кода, — до нажатия.
  проверить(с.пути('/приглашение').length === 1, 'приглашение спрошено заранее, до нажатия (' +
    с.пути('/приглашение').length + ' запрос)');
  с.узел('кнопка-позвать-друга').нажать();
  // Без await: копирование обязано случиться прямо в нажатии (Safari иначе откажет).
  проверить(с.буфер.length === 1 && с.пути('/приглашение').length === 1,
    'нажатие копирует сразу, без ожидания; /приглашение повторно не спрошено (' +
    с.пути('/приглашение').length + ')');
  await дождаться();
  const события = с.события();
  проверить(события.length === 1 && события[0] === 'скопировано',
    'компьютер, сообщение не подготовлено: события [' + события.join(', ') + '] — только «скопировано»');
  проверить(с.буфер.length === 1 && с.буфер[0] === ССЫЛКА_СЕРВЕРА,
    'в буфере ссылка сервера с номером: «' + (с.буфер[0] || '').slice(-40) + '»');

  // Телефон со старым Telegram (нет shareMessage): ссылка сервера в окне выбора чата.
  const т = await засестьЗаСтол({ сервер: сервер({ подготовил: false }), платформа: 'android' });
  т.узел('кнопка-позвать-друга').нажать();
  await дождаться();
  const открыта = т.открытыеСсылки[0] || '';
  проверить(т.события().join(',') === 'окноОткрыто',
    'телефон без выбора поверх: события [' + т.события().join(', ') + ']');
  проверить(открыта.indexOf(encodeURIComponent(ССЫЛКА_СЕРВЕРА)) !== -1,
    'в окно выбора чата ушла ссылка сервера с номером');

  // Ответ на заранее посланный запрос ещё не пришёл — ждём ТОТ ЖЕ запрос, второго нет.
  let отдатьПриглашение = null;
  const медленно = await засестьЗаСтол({
    сервер: сервер({ приглашение: function () {
      return new Promise(function (готово) {
        отдатьПриглашение = function () {
          готово(ответСервера(200, { умеем: true, ок: false, приглашение: НОМЕР, ссылка: ССЫЛКА_СЕРВЕРА }));
        };
      });
    } })
  });
  медленно.узел('кнопка-позвать-друга').нажать();
  await дождаться();
  проверить(медленно.буфер.length === 0, 'ответа ещё нет — в буфере пусто, ждём сервер');
  if (отдатьПриглашение) отдатьПриглашение();
  await дождаться();
  проверить(медленно.буфер[0] === ССЫЛКА_СЕРВЕРА && медленно.пути('/приглашение').length === 1,
    'ответ пришёл — скопирована ссылка сервера; /приглашение спрошено ' +
    медленно.пути('/приглашение').length + ' раз');
}

