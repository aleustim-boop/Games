    if (отправил) {
      // Строго два события: лишнее «отправлено» до колбэка — тоже ошибка.
      проверить(события.join(',') === 'окноОткрыто,отправлено' && номераВерны,
        'sent=true: события [' + события.join(', ') + '] — ровно окноОткрыто, отправлено; номер из ответа сервера');
    } else {
      проверить(события.indexOf('отменено') !== -1 && события.indexOf('отправлено') === -1 && номераВерны,
        'sent=false: события [' + события.join(', ') + '] — «отправлено» нет');
    }
    проверить(события.indexOf('окноОткрыто') !== -1 && события.indexOf('окноОткрыто') < события.length - 1,
      'окно открыто отмечено раньше итога: [' + события.join(', ') + ']');
