function сделатьПамять() {
  const ящик = new Map();
  return {
    getItem: function (к) { return ящик.has(к) ? ящик.get(к) : null; },
    setItem: function (к, з) { ящик.set(к, String(з)); },
    removeItem: function (к) { ящик.delete(к); }
  };
}

function ответСервера(номер, данные) {
  return Promise.resolve({
    ok: номер >= 200 && номер < 300, status: номер,
    json: function () { return Promise.resolve(данные); }
  });
}

async function дождаться() {
  for (let раз = 0; раз < 30; раз++) await new Promise(function (г) { setImmediate(г); });
}

/* Сервер, который пускает за стол и готовит приглашение. «подготовил» —
   принял ли Telegram сообщение (false — запасной путь). «опрос» — ответ
   на /что-нового (нет — молчит). */
function сервер(настройки) {
  const н = настройки || {};
  return function (путь) {
    if (путь === '/войти') {
      // Стол ещё собирается — на экране код, и кнопка «Позвать друга» видна.
      return н.войти ? н.войти() : ответСервера(200, {
        код: КОД, пропуск: 'пропуск-1',
        состояние: н.состояние || { этап: 'ожидание', код: КОД, версия: 1 }
      });
    }
    if (путь === '/приглашение') {
      if (н.приглашение) return н.приглашение();
      const данные = { умеем: true, ок: н.подготовил !== false, приглашение: НОМЕР, ссылка: ССЫЛКА_СЕРВЕРА };
      if (н.подготовил !== false) данные.номерСообщения = 'сообщение-1';
      return ответСервера(200, данные);
    }
    if (путь === '/приглашение-событие') return ответСервера(200, { ок: true });
    if (путь === '/создать') return ответСервера(200, { код: 'NEW1', пропуск: 'пропуск-2' });
    if (путь === '/что-нового' && н.опрос) return н.опрос();
    if (путь === '/друзья-за-столом' && н.друзья) return н.друзья();
    if (путь === '/друзья-позвать' && н.позвать) return н.позвать();
    return undefined;
  };
}

