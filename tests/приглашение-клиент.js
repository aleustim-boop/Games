/* ---------- 6. «В друзья» ---------- */

/** Пустой узел экрана результата: запоминает, что в него поставили. */
function сделатьГнездо(с) {
  const гнездо = сделатьУзел('гнездо-друзей', с.страница);
  const дети = [];
  гнездо.appendChild = function (ребёнок) { дети.push(ребёнок); return ребёнок; };
  Object.defineProperty(гнездо, 'textContent', {
    get: function () { return ''; },
    set: function () { дети.length = 0; }
  });
  гнездо.дети = дети;
  return гнездо;
}

const СОСЕДИ = [
  { место: 1, имя: 'Аня', статус: 'нет', ключ: 'ключ-ани' },
  { место: 2, имя: 'Боря', статус: 'друг', ключ: 'ключ-бори' },
  { место: 3, имя: 'Вера', статус: 'позван', ключ: 'ключ-веры' },
  { место: 4, имя: 'Бот', статус: 'нет', ключ: '' }
];

async function раздел6() {
  console.log('\n6. «В друзья» на экране результата');
  const позвали = [];
  const с = await засестьЗаСтол({
    сервер: сервер({
      друзья: function () { return ответСервера(200, { узналиВас: true, места: СОСЕДИ }); },
      позвать: function () { позвали.push(1); return ответСервера(200, { узналиВас: true, ок: true, статус: 'позван' }); }
    })
  });
  проверить(typeof с.окно.Сеть.кнопкаВДрузья === 'function', 'window.Сеть.кнопкаВДрузья есть');
  const гнездо = сделатьГнездо(с);
  const поставлено = await с.окно.Сеть.кнопкаВДрузья(гнездо);
  const запросДвери = с.пути('/друзья-за-столом')[0];
  проверить(Boolean(запросДвери) && запросДвери.тело.код === КОД && запросДвери.тело.пропуск === 'пропуск-1' &&
    Boolean(запросДвери.тело.initData),
    'дверь /друзья-за-столом спрошена с кодом, пропуском и подписью');
  const тексты = гнездо.дети.map(function (д) { return д.textContent; });
  проверить(поставлено === 3 && тексты.join(' | ') === 'Аня: В друзья | Боря: В друзьях | Вера: Позван',
    'по соседям: [' + тексты.join(' | ') + '] (строк ' + поставлено + '), у бота без ключа строки нет');
  const кнопкаАни = гнездо.дети[0];
  проверить(кнопкаАни.classList.contains('кнопка') && гнездо.дети[1].classList.contains('сеть-сообщение'),
    'вид из общих классов: кнопка «кнопка», подпись «сеть-сообщение»');
  кнопкаАни.нажать();
  await дождаться();
  const зов = с.пути('/друзья-позвать');
  проверить(зов.length === 1 && зов[0].тело.ключ === 'ключ-ани' && Boolean(зов[0].тело.initData),
    'нажатие зовёт /друзья-позвать с ключом Ани (' + зов.length + ' запрос)');
  проверить(кнопкаАни.textContent === 'Аня: Позван' && кнопкаАни.disabled === true,
    'после ответа на кнопке «' + кнопкаАни.textContent + '», повторно не нажать');

  // Любой ответ не 200 — кнопок нет, ничего не падает.
  for (const номер of [403, 404, 500]) {
    const отказ = await засестьЗаСтол({
      сервер: сервер({ друзья: function () { return ответСервера(номер, { ошибка: 'нет' }); } })
    });
    const пустое = сделатьГнездо(отказ);
    // В гнезде строка от прошлой партии — отказ обязан её убрать.
    пустое.appendChild({ textContent: 'Старый: В друзья' });
    const сколько = await отказ.окно.Сеть.кнопкаВДрузья(пустое);
    проверить(сколько === 0 && пустое.дети.length === 0,
      'ответ ' + номер + ': гнездо очищено (строк ' + пустое.дети.length + '), не упало');
  }
}

