  const второйАне = стол([{ номер: ВИТЯ, имя: 'Витя' }, { номер: АНЯ, имя: 'Аня' }], 30);
  проверить(второйАне.ок === false && второйАне.причина === 'уже за столом',
    'Аня уже играет — второй стол: отказ «уже за столом» (' + JSON.stringify(второйАне.причина || второйАне.код) + ')');
  if (второйАне.ок) комнаты.удалитьКомнату(второйАне.код);

  // Уход ДО своего первого хода — сдача (п. 1).
  const ходит = партии.чейХод(к.партия);
  const уходит = ходит === аня.ктоЯ ? 1 : 0;           // не тот, кто ходит: своих ходов у него ноль
  const остаётся = 1 - уходит;
  const ушедший = уходит === 0 ? аня.ктоЯ : боря.ктоЯ;
  проверить((к.игроки[ушедший].ходовВПартии || 0) === 0, 'уходящий ещё не сделал ни одного хода');
  const сНомера = итоги.length;
  const выход = await спросить('/выйти', { код: с.код, пропуск: с.пропуски[уходит] });
  проверить(выход.код === 200 && к.этап === 'конец', 'ушёл до первого хода — партия кончилась (этап ' + к.этап + ')');
  проверить(к.событие && к.событие.что === 'ушёл-сдача',
    'уход — старые слова «ушёл-сдача», не слова пропусков (' + JSON.stringify(к.событие && к.событие.что) + ')');
  const итог = итогСтола(с.код, сНомера);
  проверить(Boolean(итог), 'событие «итог» пришло слушателю');
  проверить(итог && итог.турнир === ИД_ТУРНИРА, 'итог несёт турнир (' + JSON.stringify(итог && итог.турнир) + ')');
  проверить(итог && Number.isFinite(итог.началоМс) && итог.началоМс >= создан && итог.началоМс <= Date.now(),
    'итог несёт началоМс (' + (итог && итог.началоМс) + ')');
  проверить(итог && итог.партия === ИД_ТУРНИРА + ':' + с.код + ':' + итог.началоМс,
    'ид партии = турнир:код:начало (' + JSON.stringify(итог && итог.партия) + ')');
  const номераИтога = итог ? итог.места.map(м => м.номер).sort() : [];
  проверить(номераИтога.join(',') === [АНЯ, БОРЯ].sort().join(','), 'в итоге оба номера пары');
  const местоУшедшего = итог ? итог.места.find(м => м.номер === (уходит === 0 ? АНЯ : БОРЯ)) : null;
  const местоОставшегося = итог ? итог.места.find(м => м.номер === (уходит === 0 ? БОРЯ : АНЯ)) : null;
  проверить(местоУшедшего && местоУшедшего.исход === 'поражение', 'ушедшему — поражение');
  проверить(местоОставшегося && местоОставшегося.исход === 'победа', 'оставшемуся — победа');

  const ещё = await спросить('/ход', { код: с.код, пропуск: с.пропуски[остаётся], действие: 'ещё' });
  проверить(ещё.тело.принято === false && ещё.тело.причина === СЛОВА,
    '«Ещё партию» отклонено словами (' + JSON.stringify(ещё.тело.причина) + ')');
  const пересобрать = await спросить('/ход', { код: с.код, пропуск: с.пропуски[остаётся], действие: 'пересобрать' });
  проверить(пересобрать.тело.принято === false && пересобрать.тело.причина === СЛОВА,
    'пересборка отклонена словами (' + JSON.stringify(пересобрать.тело.причина) + ')');
  проверить(к.этап === 'конец', 'стол так и стоит на конце партии');

  // Партия кончилась — того же человека снова можно посадить.
  const снова = стол([{ номер: АНЯ, имя: 'Аня' }, { номер: ВИТЯ, имя: 'Витя' }], 30);
