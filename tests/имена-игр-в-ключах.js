'use strict';

/* =====================================================================
   ЗАБЫТАЯ ИГРА В СПИСКЕ ИМЁН — проверка, которую нельзя обойти забывчивостью.

   ЗАЧЕМ ОНА ЕСТЬ. Рекорды каждой игры лежат под своим ключом, и ключ
   собирается по списку ЛАТИНСКОЕ_ИМЯ_ИГРЫ в js/telegram.js. Игра, которой
   в списке нет, получает ключ из числа. Работать это будет — но в день,
   когда имя допишут, ключ сменится, и накопленные рекорды осиротеют:
   старые останутся под числом, новые начнут копиться под именем, а человек
   увидит пустую таблицу вместо своих побед. Вернуть их будет неоткуда.

   Строку в списке забывали два раза из двух — на шашках и на шахматах.
   Поэтому она больше не держится на памяти разработчика: проверка сама
   находит все игры, которые проект называет хранилищу, и требует, чтобы
   каждая была в списке.

   Что проверяем:
     1. каждая игра, названная в вызовах saveScore/loadScore/Рейтинг,
        вписана в ЛАТИНСКОЕ_ИМЯ_ИГРЫ;
     2. латинские имена годятся для облака Telegram (только латиница,
        цифры, «_» и «-») и не повторяются — иначе две игры сложат
        рекорды в одну запись.

   Запуск:  node tests/имена-игр-в-ключах.js
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const { КОРЕНЬ } = require('./поддельный-браузер.js');

const беды = [];
function надо(условие, что) {
  if (!условие) беды.push(что);
}

/* ---------------------------------------------------------------------
   Список имён из js/telegram.js
   --------------------------------------------------------------------- */

const найденные = new Map();   // название игры → в каком файле встретилось

const текстХранилища = fs.readFileSync(path.join(КОРЕНЬ, 'js', 'telegram.js'), 'utf8');
const кусокСписка = текстХранилища.match(/ЛАТИНСКОЕ_ИМЯ_ИГРЫ\s*=\s*\{([\s\S]*?)\}/);
надо(кусокСписка !== null, 'в js/telegram.js не нашёлся список ЛАТИНСКОЕ_ИМЯ_ИГРЫ');

const имена = {};
if (кусокСписка) {
  const строки = кусокСписка[1].match(/'([^']+)'\s*:\s*'([^']+)'/g) || [];
  for (const строка of строки) {
    const пара = строка.match(/'([^']+)'\s*:\s*'([^']+)'/);
    имена[пара[1]] = пара[2];
  }
}

/* ---------------------------------------------------------------------
   Игры, которые проект называет хранилищу
   --------------------------------------------------------------------- */

/* Места, где игра называется словом. Довод «игра» стоит у каждого вызова
   на своём месте, поэтому и правил несколько: у saveScore игра — третья
   (первые две — очки и сложность), у остальных — первая. Поле «игра:»
   берём только внутри записи партии в рейтинг: просто «игра:» встречается
   и в пояснениях к коду, и один такой пример уже дал ложную тревогу
   («игра: 'телефон'» — это про устройство, а не про игру). */
const ГДЕ_ЗОВУТ_ИГРУ = [
  /loadScore\(\s*'([^']+)'/g,
  /saveScore\(\s*[^,()]+,\s*[^,()]+,\s*'([^']+)'/g,
  /Рейтинг\.(?:прочитать|очистить)\(\s*'([^']+)'/g,
  /игра:\s*'([А-Яа-яЁё]+)',/g,
  /(?:ИГРА|ИМЯ_ИГРЫ|игра)\s*=\s*'([А-Яа-яЁё]+)'/g
];

/* Смотрим только те файлы, которые вправду разговаривают с хранилищем.
   Иначе последнее правило («ИГРА = …») ловило бы любое похожее слово
   в файлах, которые к рекордам отношения не имеют. */
function говоритСХранилищем(текст) {
  return текст.indexOf('saveScore') !== -1 ||
         текст.indexOf('loadScore') !== -1 ||
         текст.indexOf('Рейтинг.') !== -1;
}

/* Слова, которые попадаются в тех же местах, но игрой не являются. */
const НЕ_ИГРЫ = ['undefined', 'null', 'телефон', 'компьютер'];

for (const файл of fs.readdirSync(path.join(КОРЕНЬ, 'js'))) {
  if (!файл.endsWith('.js')) continue;
  /* Сам js/telegram.js пропускаем: он не называет игру, а разбирает
     чужие названия, и его собственный код («игра: ' + игра») ловится
     правилами как несуществующая игра. */
  if (файл === 'telegram.js') continue;
  const текст = fs.readFileSync(path.join(КОРЕНЬ, 'js', файл), 'utf8');
  if (!говоритСХранилищем(текст)) continue;
  for (const правило of ГДЕ_ЗОВУТ_ИГРУ) {
    правило.lastIndex = 0;
    let найдено;
    while ((найдено = правило.exec(текст)) !== null) {
      const игра = найдено[1];
      if (НЕ_ИГРЫ.indexOf(игра) !== -1) continue;
      if (!найденные.has(игра)) найденные.set(игра, файл);
    }
  }
}

надо(найденные.size > 0, 'ни одной игры не нашлось — правила поиска сломались, а не проект стал чист');

for (const [игра, файл] of найденные) {
  надо(Object.prototype.hasOwnProperty.call(имена, игра),
    'игра «' + игра + '» (встречается в js/' + файл + ') не вписана в ЛАТИНСКОЕ_ИМЯ_ИГРЫ ' +
    'в js/telegram.js. Впишите её СЕЙЧАС: допишете позже — ключ сменится, ' +
    'и накопленные рекорды этой игры пропадут для человека навсегда.');
}

/* ---------------------------------------------------------------------
   Сами латинские имена: годны для облака и не повторяются
   --------------------------------------------------------------------- */

const ПРАВИЛО_КЛЮЧА_ОБЛАКА = /^[A-Za-z0-9_-]+$/;
const занятые = {};

for (const игра of Object.keys(имена)) {
  const латинское = имена[игра];
  надо(ПРАВИЛО_КЛЮЧА_ОБЛАКА.test(латинское),
    'имя «' + латинское + '» (игра «' + игра + '») не годится для облака Telegram: ' +
    'там можно только латинские буквы, цифры, «_» и «-»');
  надо(!занятые[латинское],
    'имя «' + латинское + '» занято дважды («' + занятые[латинское] + '» и «' + игра + '») — ' +
    'рекорды двух игр сложились бы в одну запись');
  занятые[латинское] = игра;
}

if (беды.length) {
  console.log('ПЛОХО, бед ' + беды.length + ':');
  for (const беда of беды) console.log('  — ' + беда);
  process.exit(1);
}
console.log('имена игр в ключах: всё хорошо — найдено игр ' + найденные.size +
  ', все вписаны в список, латинские имена годны для облака и не повторяются');
process.exit(0);
