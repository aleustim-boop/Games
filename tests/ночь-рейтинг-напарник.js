/* =====================================================================
   РЕЙТИНГ: ГОСТЬ-НАПАРНИК И ГОСТИ В ОГРАНИЧИТЕЛЕ СГОВОРА.

   Что проверяем. Гость без Telegram (номера нет) раньше узнавался
   напарником только по номеру — то есть никогда: в «2 на 2» он шёл
   соперником. Правило владельца 30.09: «за напарника 0». Теперь
   напарника узнают по полю «сторона», которое кладёт застольеДляРейтинга
   (server/комнаты.js). Застолье здесь — НАСТОЯЩЕЕ, из комнаты; очки
   считает настоящий server/рейтинг.js.

   Сценарии:
     1) ничья парами, у человека напарник — гость: ему 5 + 5 = 10 за двух
        соперников, а не 15 (за гостя-напарника 0);
     2) пара победила, а гость-напарник ушёл посреди партии (сдался):
        человеку 10 + 10 = 20, без лишних 10 за «обыгранного» напарника;
     3) два разных гостя не склеиваются в одного: три партии втроём
        с двумя гостями, каждый раз обыгран второй гость — 30 очков.
        При общем ключе "null" шестая отметка гостей съедала зачёт;
     4) застолье без стороны (старые вызовы) — напарник по-прежнему
        узнаётся по номеру.

   УМЕЕТ КРАСНЕТЬ (каждая порча — на КОПИИ во временной папке системы,
   файлы проекта не трогаются):
     node tests/ночь-рейтинг-напарник.js --сломать=1   застолье без стороны
     node tests/ночь-рейтинг-напарник.js --сломать=2   рейтинг ищет напарника
                                                       только по номеру (как было)
     node tests/ночь-рейтинг-напарник.js --сломать=3   гости снова идут через
                                                       ограничитель одним ключом "null"
     node tests/ночь-рейтинг-напарник.js --сломать=4   сторона одна на всех за столом
     node tests/ночь-рейтинг-напарник.js --сломать=все прогоняет все порчи
                                                       и требует провала каждой

   Запуск: node tests/ночь-рейтинг-напарник.js
   Выход 0 — провалов нет.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const ПРОЕКТ = path.join(__dirname, '..');

/* Порчи: в каком файле, что заменить, на что. Каждая обязана уронить
   хотя бы один сценарий выше. Строка «было» должна встречаться в файле
   ровно один раз — иначе приём устарел, и проверка говорит это вслух. */
const ПОРЧИ = {
  1: {
    что: 'застолье без стороны',
    файл: 'server/комнаты.js',
    было: "сторона: местоНапарника ? [место, местоНапарника].sort().join('+') : null,",
    стало: 'сторона: null,'
  },
  2: {
    что: 'напарник только по номеру',
    файл: 'server/рейтинг.js',
    было: 'const этоНапарник = напарникЗаСтолом(игрок, другой);',
    стало: 'const этоНапарник = Boolean(игрок.напарник) && Boolean(другой) && другой.номер === игрок.напарник;'
  },
  3: {
    что: 'гости в ограничителе одним ключом',
    файл: 'server/рейтинг.js',
    было: 'const гостьБезНомера = !этоБот && !этоНомерИгрока(другой && другой.номер);',
    стало: 'const гостьБезНомера = false;'
  },
  4: {
    что: 'сторона одна на всех',
    файл: 'server/комнаты.js',
    было: "сторона: местоНапарника ? [место, местоНапарника].sort().join('+') : null,",
    стало: "сторона: 'стол',"
  }
};

const флагПорчи = process.argv.find(function (д) { return д.indexOf('--сломать') === 0; });
const ПОРЧА = флагПорчи ? флагПорчи.split('=')[1] : null;

if (флагПорчи && !ПОРЧА) {
  console.error('ОШИБКА: укажите номер порчи: --сломать=1…' + Object.keys(ПОРЧИ).length + ' или --сломать=все');
  process.exit(2);
}

/* --сломать=все: каждую порчу гоняем отдельным процессом и требуем провала
   (выход 1). Зелёная порча — провал самой проверки. */
if (ПОРЧА === 'все') {
  let плохих = 0;
  for (const номер of Object.keys(ПОРЧИ)) {
    const прогон = spawnSync(process.execPath, [__filename, '--сломать=' + номер], { encoding: 'utf8' });
    const покраснела = прогон.status === 1;
    if (!покраснела) плохих++;
    console.log((покраснела ? '  ✓' : '  ✗') + ' порча ' + номер + ' (' + ПОРЧИ[номер].что + '): выход ' + прогон.status +
      (покраснела ? ', проверка покраснела' : ' — ждали 1') + (прогон.status === 2 ? '\n' + прогон.stderr : ''));
  }
  console.log('\nИтого проверок: ' + Object.keys(ПОРЧИ).length + ', провалов: ' + плохих);
  process.exit(плохих ? 1 : 0);
}

if (ПОРЧА && !ПОРЧИ[ПОРЧА]) {
  console.error('ОШИБКА: порчи «' + ПОРЧА + '» нет; есть: ' + Object.keys(ПОРЧИ).join(', ') + ', все');
  process.exit(2);
}

/** Заменить ровно одно вхождение, иначе приём порчи устарел — сказать вслух. */
function заменитьРовноОдин(файл, старое, новое) {
  const части = fs.readFileSync(файл, 'utf8').split(старое);
  if (части.length !== 2) {
    console.error('ОШИБКА: приём порчи устарел: «' + старое + '» встречается в ' + файл + ' ' +
      (части.length - 1) + ' раз(а) вместо одного — поправьте проверку тем же коммитом');
    process.exit(2);
  }
  fs.writeFileSync(файл, части.join(новое), 'utf8');
}

/** Откуда брать код: из проекта или из испорченной копии во временной папке. */
function папкаКода() {
  if (!ПОРЧА) return ПРОЕКТ;
  const порча = ПОРЧИ[ПОРЧА];
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'ночь-рейтинг-напарник-сломать-'));
  // Боевые данные в копию не везём — они не нужны и не наши.
  const безДанных = function (откуда) {
    const имя = path.basename(откуда);
    return имя !== 'данные' && имя !== 'node_modules';
  };
  fs.cpSync(path.join(ПРОЕКТ, 'server'), path.join(папка, 'server'), { recursive: true, filter: безДанных });
  fs.cpSync(path.join(ПРОЕКТ, 'js'), path.join(папка, 'js'), { recursive: true });
  заменитьРовноОдин(path.join(папка, порча.файл), порча.было, порча.стало);
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК ' + ПОРЧА + ' (' + порча.что + '): код из копии ' + папка +
    ' — прогон обязан провалиться ***\n');
  return папка;
}

const КОД = папкаКода();
// Папку данных уводим ДО подключения комнат: рейтинг пишет туда свою память.
process.env.GAMES_DATA = fs.mkdtempSync(path.join(os.tmpdir(), 'ночь-рейтинг-напарник-данные-'));
// Комнаты подключают рейтинг сами — берём тот же самый файл (один модуль на двоих).
const комнаты = require(path.join(КОД, 'server', 'комнаты.js'));
const рейтинг = require(path.join(КОД, 'server', 'рейтинг.js'));
// Имена мест — из того же файла, что раздаёт их комнатам, а не своей копией.
const МЕСТА = require(path.join(КОД, 'server', 'партия-по-сети.js')).МЕСТА;
const ЗА_ЧЕЛОВЕКА = рейтинг.ЦЕНА.человек;

let всегоПроверок = 0;
let ошибок = 0;

function равно(что, было, надо) {
  всегоПроверок++;
  const ок = было === надо;
  if (!ок) ошибок++;
  console.log((ок ? '  ✓' : '  ✗') + ' ' + что + ': ' + было + (ок ? '' : ' (ждали ' + надо + ')'));
}

function человек(номер) { return { телеграм: номер, имя: 'П' + номер, этоБот: false }; }
function гость(имя) { return { телеграм: null, имя: имя, этоБот: false }; }
/** Гость, вышедший посреди партии на столе вчетвером: место водит бот, пометка «сдался». */
function ушедшийГость(имя) {
  return { телеграм: null, имя: имя, этоБот: true, уровень: 'обычный', ушёл: true, сдался: true };
}

/**
 * Комната с кончившейся партией — в тех полях, что читает застольеДляРейтинга.
 * сидят — по местам по порядку; проигравшие — номера мест (с нуля).
 */
function комнатаСИтогом(игра, сидят, настройки) {
  const места = МЕСТА.slice(0, сидят.length);
  const игроки = {};
  места.forEach(function (место, и) {
    игроки[место] = Object.assign({ сдался: false }, сидят[и]);
  });
  const парами = настройки.парами === true;
  return {
    игра: игра, мест: места.length, парами: парами, переводной: false, уровеньБотов: 'обычный',
    игроки: игроки,
    партия: {
      завершена: true,
      ничья: настройки.ничья === true,
      проигравшие: (настройки.проигравшие || []).map(function (и) { return места[и]; }),
      игроки: места.slice(),
      парами: парами
    }
  };
}

/** Настоящее застолье комнаты; пустое или неполное — провал вслух. */
function застольеКомнаты(комната) {
  const застолье = комнаты.застольеДляРейтинга(комната);
  равно('   застолье: строк столько же, сколько сидит', застолье.length, Object.keys(комната.игроки).length);
  return застолье;
}

/** В игре парами: у напарников (места 0↔2, 1↔3) сторона одна, у соперников — разная. */
function сторонаКакНадо(застолье) {
  равно('   застолье: сторона места 0 есть', typeof застолье[0].сторона === 'string' && застолье[0].сторона !== '', true);
  равно('   застолье: у места 0 и его напарника 2 сторона одна', застолье[0].сторона === застолье[2].сторона, true);
  равно('   застолье: у места 1 и его напарника 3 сторона одна', застолье[1].сторона === застолье[3].сторона, true);
  равно('   застолье: у соперников (0 и 1) стороны разные', застолье[0].сторона !== застолье[1].сторона, true);
}

function очки(номер, игра) {
  const срез = рейтинг.срезДляИгрока(игра || 'дурак', номер);
  return срез.я ? срез.я.очки : 0;
}

console.log('=== Рейтинг: гость-напарник и гости в ограничителе сговора ===\n');

console.log('1. Ничья парами: напарник человека 401 — гость без Telegram');
рейтинг.забытьВсё();
const застольеНичьи = застольеКомнаты(комнатаСИтогом('дурак',
  [человек(401), человек(402), гость('Гость'), человек(404)], { парами: true, ничья: true }));
сторонаКакНадо(застольеНичьи);
const итогНичьи = рейтинг.учестьПартию('дурак', застольеНичьи);
равно('401: ничья за двух соперников, за гостя-напарника 0', итогНичьи[401], ЗА_ЧЕЛОВЕКА.ничья * 2);
равно('402: ничья за двух соперников (401 и гость), за напарника 404 — 0', итогНичьи[402], ЗА_ЧЕЛОВЕКА.ничья * 2);
равно('404: так же', итогНичьи[404], ЗА_ЧЕЛОВЕКА.ничья * 2);

console.log('\n2. Пара (501 + гость) победила, гость ушёл посреди партии');
рейтинг.забытьВсё();
const застольеУхода = застольеКомнаты(комнатаСИтогом('дурак',
  [человек(501), человек(502), ушедшийГость('Гость'), человек(504)], { парами: true, проигравшие: [1, 3] }));
сторонаКакНадо(застольеУхода);
равно('   застолье: ушедший гость — человек с поражением', застольеУхода[2].этоБот === false && застольеУхода[2].победил === false, true);
const итогУхода = рейтинг.учестьПартию('дурак', застольеУхода);
равно('501: 10 + 10 за обыгранных соперников, за ушедшего напарника 0', итогУхода[501], ЗА_ЧЕЛОВЕКА.победа * 2);
равно('502: проигравший', итогУхода[502], 0);

console.log('\n3. Два разных гостя не склеиваются: 601 трижды играет втроём с гостями А и Б');
рейтинг.забытьВсё();
let заТриПартии = 0;
for (let и = 0; и < 3; и++) {
  // Обыгран всегда гость Б (место 2): при общем ключе "null" его отметка шестая.
  const итог = рейтинг.учестьПартию('дурак', застольеКомнаты(комнатаСИтогом('дурак',
    [человек(601), гость('Гость А'), гость('Гость Б')], { проигравшие: [2] })));
  заТриПартии += итог[601];
}
равно('601: три победы над гостем Б — по полной цене', заТриПартии, ЗА_ЧЕЛОВЕКА.победа * 3);
// Сценарий имеет смысл, только если шесть отметок под одним ключом уже сверх зачёта.
равно('   сценарий честный: 6 отметок гостей больше дневного зачёта пары',
  рейтинг.ПАРТИЙ_С_ОДНИМ_ЧЕЛОВЕКОМ_В_СУТКИ < 6, true);

console.log('\n4. Застолье без стороны (старые вызовы): напарник по номеру');
рейтинг.забытьВсё();
const безСтороны = застольеКомнаты(комнатаСИтогом('дурак',
  [человек(701), человек(702), человек(703), человек(704)], { парами: true, проигравшие: [1, 3] }))
  .map(function (строка) { return Object.assign({}, строка, { сторона: undefined }); });
const итогБезСтороны = рейтинг.учестьПартию('дурак', безСтороны);
равно('701: 10 + 10, за напарника 703 — 0', итогБезСтороны[701], ЗА_ЧЕЛОВЕКА.победа * 2);

console.log('\n----------------------------------------');
console.log('Итого проверок: ' + всегоПроверок + ', провалов: ' + ошибок);
process.exit(ошибок ? 1 : 0);
