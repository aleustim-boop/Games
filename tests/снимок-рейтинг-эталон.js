async function замерыВысот(страница) {
  return страница.evaluate(() => {
    const результат = {
      детиЭкрана: [],
      нижниеВкладки: null,
      экран: null
    };

    const экран = document.getElementById('экран-рейтинга-игроков');
    if (!экран) return результат;

    // Высоты прямых детей экрана
    Array.prototype.forEach.call(экран.children, (дитя) => {
      const id = дитя.id || '';
      const класс = дитя.className || '';
      const offH = дитя.offsetHeight;
      const rect = дитя.getBoundingClientRect();
      результат.детиЭкрана.push({
        элемент: id ? '#' + id : '.' + класс.split(/\s+/)[0],
        высота: offH,
        top: Math.round(rect.top),
        bottom: Math.round(rect.bottom)
      });
    });

    // Нижние вкладки
    const нижниеВкладки = экран.querySelector('.нижние-вкладки');
    if (нижниеВкладки) {
      const rectНав = нижниеВкладки.getBoundingClientRect();
      результат.нижниеВкладки = {
        высота: нижниеВкладки.offsetHeight,
        top: Math.round(rectНав.top),
        bottom: Math.round(rectНав.bottom)
      };
    }

    // Сам экран
    const rectЭкран = экран.getBoundingClientRect();
    const compStyle = window.getComputedStyle(экран);
    результат.экран = {
      clientHeight: экран.clientHeight,
      scrollHeight: экран.scrollHeight,
      offsetHeight: экран.offsetHeight,
      top: Math.round(rectЭкран.top),
      bottom: Math.round(rectЭкран.bottom),
      paddingBottom: compStyle.paddingBottom
    };

    return результат;
  });
}

// Пункт г) — сырые числа для планирования следующей вёрстки: высота
// подиума и самого списка, scrollHeight списка, сколько строк
// .рейтинг-строка (без шапки) видно ЦЕЛИКОМ без прокрутки. Печать без
// проверок — штабу нужны числа, не зелёный/красный.
async function замерыСпискаИПодиума(страница) {
  return страница.evaluate(() => {
    const таблица = document.getElementById('рейтинг-таблица');
    if (!таблица) return null;
    const подиум = таблица.querySelector('.рейтинг-подиум');
    const rectТабл = таблица.getBoundingClientRect();
    const строки = Array.prototype.slice.call(таблица.querySelectorAll('.рейтинг-строка'))
      .filter((с) => !с.classList.contains('рейтинг-строка--шапка'));
    let видноЦеликом = 0;
    строки.forEach((с) => {
      const r = с.getBoundingClientRect();
      if (r.top >= rectТабл.top - 0.5 && r.bottom <= rectТабл.bottom + 0.5) видноЦеликом++;
    });
    return {
      найденПодиум: Boolean(подиум),
      высотаПодиума: подиум ? Math.round(подиум.getBoundingClientRect().height) : null,
      высотаТаблицы: Math.round(rectТабл.height),
      offsetHeightТаблицы: таблица.offsetHeight,
      scrollHeightСписка: таблица.scrollHeight,
      строкВсего: строки.length,
      строкВидноЦеликом: видноЦеликом
    };
  });
}

