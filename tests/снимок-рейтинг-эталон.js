/* ---------------------------------------------------------------------
   Навешать перехват и слушателей консоли/сети на страницу. Возвращает
   объект со ссылками на массивы — заполняются по ходу всего прогона
   на этой странице (страница живёт несколько снимков подряд).
   --------------------------------------------------------------------- */

async function подготовитьСтраницу(страница) {
  const красные = [];
  const сетевыеОшибки = [];
  const картинкиРейтинга = [];

  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const т = м.text();
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js|telegram\.org/.test(т + ' ' + откуда)) return;
    красные.push('консоль: ' + т + (откуда ? ' [' + откуда + ']' : ''));
  });
  страница.on('response', (ответ) => {
    let адрес = ответ.url();
    try { адрес = decodeURIComponent(адрес); } catch (е) { /* оставим как есть */ }
    const статус = ответ.status();
    if (адрес.indexOf('img/рейтинг') !== -1) картинкиРейтинга.push({ адрес: адрес, статус: статус });
    if (статус >= 400) сетевыеОшибки.push('[' + статус + '] ' + адрес);
  });

  await подготовитьПодделку(страница, { версия: '8.0' });

  let перехватов = 0;
  const ДВЕРЬ_РЕЙТИНГА = new RegExp('/рейтинг(?:\\?|$)');
  await перехватить(страница, ДВЕРЬ_РЕЙТИНГА, function (путь, запрос) {
    перехватов++;
    let игра = 'все';
    try {
      const тело = JSON.parse((запрос.postData && запрос.postData()) || '{}');
      if (тело && тело.игра) игра = тело.игра;
    } catch (о) { /* тела может не быть */ }
    путь.fulfill({
      status: 200,
      contentType: 'application/json; charset=utf-8',
      body: JSON.stringify(ответДвериРейтинга(игра))
    });
  });

  return {
    красные: красные,
    сетевыеОшибки: сетевыеОшибки,
    картинкиРейтинга: картинкиРейтинга,
    перехватов: () => перехватов
  };
}

/* ---------------------------------------------------------------------
   Замеры экрана рейтинга через page.evaluate — одним вызовом собираем
   всё, что нужно для текущего снимка. Устройство узлов (id/классы)
   читается по тем же именам, что рисует js/рейтинг-экран.js — вторая
   копия селекторов внутри проверки не заводится, приём тот же, что и в
   снимок-рейтинг-золото.js.
   --------------------------------------------------------------------- */

async function замерыЭкрана(страница) {
  return страница.evaluate(() => {
    const р = { найдено: {} };

    const экран = document.getElementById('экран-рейтинга-игроков');
    р.найдено.экран = Boolean(экран);
    if (!экран) return р;

    // Подиум первой тройки. Карточки идут в DOM-порядке 2-1-3 (см.
    // js/рейтинг-экран.js, «подиумУзел») — «первая по документу» это
    // место 2, а корона рисуется ТОЛЬКО у карточки места 1, поэтому для
    // короны и её геометрии ищем карточку именно по data-место="1",
    // а не первую по document order.
    const карточкиПодиума = Array.prototype.slice.call(экран.querySelectorAll('.рейтинг-подиум-карточка'));
    р.найдено.карточекПодиума = карточкиПодиума.length;
    р.местаПодиума = карточкиПодиума.map((к) => к.getAttribute('data-место')).join(',');
    const перваяКарточка = карточкиПодиума[0] || null;
    const карточкаПервогоМеста = экран.querySelector('.рейтинг-подиум-карточка[data-место="1"]');
    if (перваяКарточка) {
      const имя = перваяКарточка.querySelector('.рейтинг-подиум-имя');
      const очки = перваяКарточка.querySelector('.рейтинг-подиум-очки');
      р.найдено.имяВТумбе = Boolean(имя) && Boolean(имя.textContent.trim());
      р.найдено.очкиВТумбе = Boolean(очки) && Boolean(очки.textContent.trim());
      const медаль = перваяКарточка.querySelector('.рейтинг-подиум-медаль');
      р.найдено.медаль = Boolean(медаль);
    }
    р.найдено.карточкаПервогоМеста = Boolean(карточкаПервогоМеста);
    if (карточкаПервогоМеста) {
      const rect = карточкаПервогоМеста.getBoundingClientRect();
      р.карточкаПервогоМестаRect = { top: rect.top, left: rect.left, width: rect.width, height: rect.height };
      const корона = карточкаПервогоМеста.querySelector('.рейтинг-подиум-корона');
      р.найдено.корона = Boolean(корона);
      if (корона) {
        const rectКорона = корона.getBoundingClientRect();
        р.коронаRect = { top: rectКорона.top, left: rectКорона.left, width: rectКорона.width, height: rectКорона.height };
      }
    }

    // Шапка (заголовок + кнопка «i»)
    const шапка = экран.querySelector('.рейтинг-шапка') || document.getElementById('рейтинг-шапка');
    р.найдено.шапка = Boolean(шапка);
    if (шапка) {
      const rect = шапка.getBoundingClientRect();
      р.шапкаRect = { top: rect.top, bottom: rect.bottom, left: rect.left, right: rect.right };
    }
    const кнопкаИнфо = document.getElementById('кнопка-рейтинг-инфо');
    р.найдено.кнопкаИнфо = Boolean(кнопкаИнфо) && кнопкаИнфо.textContent.trim() === 'i';

    // Сегмент «Все игроки | Друзья»
    const круг = document.getElementById('рейтинг-круг') || экран.querySelector('.рейтинг-круг');
    р.найдено.круг = Boolean(круг);
    if (круг) {
      const кнопкиКруга = Array.prototype.slice.call(круг.querySelectorAll('[data-круг]'));
      р.найдено.кнопокКруга = кнопкиКруга.length;
      р.текстыКруга = кнопкиКруга.map((к) => к.textContent.trim());
      const активная = кнопкиКруга.find((к) => к.classList.contains('переключатель__вариант--выбран'));
      р.активныйКруг = активная ? активная.getAttribute('data-круг') : null;
    }

    // Заголовок списка «Место / Игрок / Очки»
    const шапкаСписка = экран.querySelector('.рейтинг-строка--шапка');
    р.найдено.шапкаСписка = Boolean(шапкаСписка);
    р.текстШапкиСписка = шапкаСписка ? шапкаСписка.textContent.replace(/\s+/g, ' ').trim() : '';

    // Своя строка (пилюля «Вы») — вне подиума, отдельной строкой списка
    const своиСтроки = Array.prototype.slice.call(экран.querySelectorAll('.рейтинг-строка--я'));
    р.найдено.своихСтрок = своиСтроки.length;
    р.текстСвоейСтроки = своиСтроки[0] ? своиСтроки[0].textContent.replace(/\s+/g, ' ').trim() : '';

    // Текст «моё место» / пояснения (для сценария «друзья пусто»)
    const моёМесто = document.getElementById('рейтинг-моё-место');
    р.текстМоёМесто = моёМесто ? моёМесто.textContent.trim() : '';

    // Кнопка «Добавить друга» (только когда друзей нет)
    const кнопки = Array.prototype.slice.call(экран.querySelectorAll('#рейтинг-таблица button'));
    р.найдено.кнопкаДобавитьДруга = кнопки.some((к) => к.textContent.trim() === 'Добавить друга');

    // Нижняя полоса вкладок с активной «Рейтинг»
    const nav = экран.querySelector('.нижние-вкладки[data-вкладки="рейтинг"]');
    р.найдено.нижниеВкладки = Boolean(nav);
    if (nav) {
      const активнаяВкладка = nav.querySelector('.нижняя-вкладка--активна');
      р.найдено.активнаяВкладка = Boolean(активнаяВкладка);
      р.текстАктивнойВкладки = активнаяВкладка ? активнаяВкладка.textContent.replace(/\s+/g, ' ').trim() : '';
      const navRect = nav.getBoundingClientRect();
      р.нижниеВкладкиRect = { top: navRect.top, bottom: navRect.bottom };
    }

    // Замеры ширины аватаров подиума
    const аватарМеста1 = экран.querySelector('.рейтинг-подиум-карточка[data-место="1"] .рейтинг-подиум-аватар');
    const аватарыМест23 = Array.prototype.slice.call(экран.querySelectorAll('.рейтинг-подиум-карточка[data-место="2"] .рейтинг-подиум-аватар, .рейтинг-подиум-карточка[data-место="3"] .рейтинг-подиум-аватар'));
    р.ширинаАватара1 = аватарМеста1 ? Math.round(аватарМеста1.getBoundingClientRect().width) : null;
    р.ширинаАватара23 = аватарыМест23.map((а) => Math.round(а.getBoundingClientRect().width));

    // Карточка «Моё место»
    const моёМестоКарточка = document.getElementById('рейтинг-моё-место');
    if (моёМестоКарточка) {
      const rectМоёМесто = моёМестоКарточка.getBoundingClientRect();
      р.моёМестоRect = { top: rectМоёМесто.top, bottom: rectМоёМесто.bottom };
    }

    // scrollHeight и clientHeight экрана и документа
    р.экранScrollHeight = экран.scrollHeight;
    р.экранClientHeight = экран.clientHeight;
    р.docScrollHeight = document.documentElement.scrollHeight;
    р.docClientHeight = window.innerHeight;

    // Узлы движения в таблице
    const узлыДвижения = Array.prototype.slice.call(экран.querySelectorAll('.рейтинг-движение'));
    р.узлыДвижения = узлыДвижения.map((у) => ({
      текст: у.textContent.trim(),
      класс: у.className
    }));
    р.найдено.узлыДвиженияСоСтрелками = узлыДвижения.some((у) => /^[↑↓]/.test(у.textContent));

    return р;
  });
}

async function замерыШирины(страница) {
  return страница.evaluate(() => {
    function offsetWidthОf(селектор) {
      const узел = document.querySelector(селектор);
      return узел ? узел.offsetWidth : null;
    }
    return {
      экран: offsetWidthОf('#экран-рейтинга-игроков'),
      таблица: offsetWidthОf('#рейтинг-таблица'),
      перваяКарточкаПодиума: offsetWidthОf('.рейтинг-подиум-карточка')
    };
  });
}

async function замерыВысот(страница) {
  return страница.evaluate(() => {
    const результат = {
      детиЭкрана: [],
      нижниеВкладки: null,
      экран: null
    };

    const экран = document.getElementById('экран-рейтинга-игроков');
    if (!экран) return результат;

    // Высоты прямых детей экрана
    Array.prototype.forEach.call(экран.children, (дитя) => {
      const id = дитя.id || '';
      const класс = дитя.className || '';
      const offH = дитя.offsetHeight;
      const rect = дитя.getBoundingClientRect();
      результат.детиЭкрана.push({
        элемент: id ? '#' + id : '.' + класс.split(/\s+/)[0],
        высота: offH,
        top: Math.round(rect.top),
        bottom: Math.round(rect.bottom)
      });
    });

    // Нижние вкладки
    const нижниеВкладки = экран.querySelector('.нижние-вкладки');
    if (нижниеВкладки) {
      const rectНав = нижниеВкладки.getBoundingClientRect();
      результат.нижниеВкладки = {
        высота: нижниеВкладки.offsetHeight,
        top: Math.round(rectНав.top),
        bottom: Math.round(rectНав.bottom)
      };
    }

    // Сам экран
    const rectЭкран = экран.getBoundingClientRect();
    const compStyle = window.getComputedStyle(экран);
    результат.экран = {
      clientHeight: экран.clientHeight,
      scrollHeight: экран.scrollHeight,
      offsetHeight: экран.offsetHeight,
      top: Math.round(rectЭкран.top),
      bottom: Math.round(rectЭкран.bottom),
      paddingBottom: compStyle.paddingBottom
    };

    return результат;
  });
}

