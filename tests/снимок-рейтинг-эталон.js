/* ---------------------------------------------------------------------
   Навешать перехват и слушателей консоли/сети на страницу. Возвращает
   объект со ссылками на массивы — заполняются по ходу всего прогона
   на этой странице (страница живёт несколько снимков подряд).
   --------------------------------------------------------------------- */

async function подготовитьСтраницу(страница) {
  const красные = [];
  const сетевыеОшибки = [];
  const картинкиРейтинга = [];

  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const т = м.text();
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js|telegram\.org/.test(т + ' ' + откуда)) return;
    красные.push('консоль: ' + т + (откуда ? ' [' + откуда + ']' : ''));
  });
  страница.on('response', (ответ) => {
    let адрес = ответ.url();
    try { адрес = decodeURIComponent(адрес); } catch (е) { /* оставим как есть */ }
    const статус = ответ.status();
    if (адрес.indexOf('img/рейтинг') !== -1) картинкиРейтинга.push({ адрес: адрес, статус: статус });
    if (статус >= 400) сетевыеОшибки.push('[' + статус + '] ' + адрес);
  });

  await подготовитьПодделку(страница, { версия: '8.0' });

  let перехватов = 0;
  /* ОДИН обработчик на дверь /рейтинг и на фоновые двери /статистика,
     /пульс, /мой-аватар — как в tests/снимок-рейтинг-золото.js. Второй
     параллельный page.route() эти правила не складывает, а МЕНЯЕТ (playwright
     отдаёт запрос последнему подходящему), поэтому все двери — в одном
     обработчике. Без ответа на /статистика и /пульс страница честно стучится
     на боевой 8790, которого при проверке нет: ERR_CONNECTION_REFUSED сыплется
     в консоль красными строками и топит проверку «в консоли нет ошибок» —
     это шум самой проверки, не поломка игры. */
  const ДВЕРИ_РЕЙТИНГА = new RegExp('/(?:рейтинг(?:\\?|$)|статистика(?:\\?|$)|пульс(?:\\?|$)|мой-аватар(?:\\?|$))');
  await перехватить(страница, ДВЕРИ_РЕЙТИНГА, function (путь, запрос, адрес) {
    if (!/\/рейтинг(?:\?|$)/.test(адрес || '')) {
      путь.fulfill({ status: 200, contentType: 'application/json; charset=utf-8', body: JSON.stringify({ ок: false }) });
      return;
    }
    перехватов++;
    let игра = 'все';
    try {
      const тело = JSON.parse((запрос.postData && запрос.postData()) || '{}');
      if (тело && тело.игра) игра = тело.игра;
    } catch (о) { /* тела может не быть */ }
    путь.fulfill({
      status: 200,
      contentType: 'application/json; charset=utf-8',
      body: JSON.stringify(ответДвериРейтинга(игра))
    });
  });

  return {
    красные: красные,
    сетевыеОшибки: сетевыеОшибки,
    картинкиРейтинга: картинкиРейтинга,
    перехватов: () => перехватов
  };
}

/* ---------------------------------------------------------------------
   Замеры экрана рейтинга через page.evaluate — одним вызовом собираем
   всё, что нужно для текущего снимка. Устройство узлов (id/классы)
   читается по тем же именам, что рисует js/рейтинг-экран.js — вторая
   копия селекторов внутри проверки не заводится, приём тот же, что и в
   снимок-рейтинг-золото.js.
   --------------------------------------------------------------------- */

async function замерыЭкрана(страница) {
  return страница.evaluate(() => {
    const р = { найдено: {} };

    const экран = document.getElementById('экран-рейтинга-игроков');
    р.найдено.экран = Boolean(экран);
    if (!экран) return р;

    // Подиум первой тройки. Карточки идут в DOM-порядке 2-1-3 (см.
    // js/рейтинг-экран.js, «подиумУзел») — «первая по документу» это
    // место 2, а корона рисуется ТОЛЬКО у карточки места 1, поэтому для
    // короны и её геометрии ищем карточку именно по data-место="1",
    // а не первую по document order.
    const карточкиПодиума = Array.prototype.slice.call(экран.querySelectorAll('.рейтинг-подиум-карточка'));
    р.найдено.карточекПодиума = карточкиПодиума.length;
    р.местаПодиума = карточкиПодиума.map((к) => к.getAttribute('data-место')).join(',');
    const перваяКарточка = карточкиПодиума[0] || null;
    const карточкаПервогоМеста = экран.querySelector('.рейтинг-подиум-карточка[data-место="1"]');
    if (перваяКарточка) {
      const имя = перваяКарточка.querySelector('.рейтинг-подиум-имя');
      const очки = перваяКарточка.querySelector('.рейтинг-подиум-очки');
      р.найдено.имяВТумбе = Boolean(имя) && Boolean(имя.textContent.trim());
      р.найдено.очкиВТумбе = Boolean(очки) && Boolean(очки.textContent.trim());
      const медаль = перваяКарточка.querySelector('.рейтинг-подиум-медаль');
      р.найдено.медаль = Boolean(медаль);
    }
    р.найдено.карточкаПервогоМеста = Boolean(карточкаПервогоМеста);
    if (карточкаПервогоМеста) {
      const rect = карточкаПервогоМеста.getBoundingClientRect();
      р.карточкаПервогоМестаRect = { top: rect.top, left: rect.left, width: rect.width, height: rect.height };
      const корона = карточкаПервогоМеста.querySelector('.рейтинг-подиум-корона');
      р.найдено.корона = Boolean(корона);
      if (корона) {
        const rectКорона = корона.getBoundingClientRect();
        р.коронаRect = { top: rectКорона.top, left: rectКорона.left, width: rectКорона.width, height: rectКорона.height };
      }
      // Недочёт «Г2»: ореол первого места — «::before» у самой карточки
      // (правило «...карточка[data-место="1"]::before» в style.css).
      // Читаем вычисленный стиль псевдоэлемента напрямую — свой узел
      // у «::before» не бывает, querySelector его не находит.
      const стильОреола = window.getComputedStyle(карточкаПервогоМеста, '::before');
      // Возврат «css-Б2», беда 3: «тень есть» и «шире аватара» не ловят
      // «тонкий и сухой» ореол — нужны настоящие числа размытия (blur),
      // растяжения (spread) и непрозрачности (alpha) самой тени, чтобы
      // проверка отличала яркий размытый ореол от еле заметного. Blur и
      // spread — третье и четвёртое px-числа в computed box-shadow
      // (порядок offsetX, offsetY, blur, spread). Альфа — последнее
      // число цвета перед закрывающей скобкой: у color-mix() браузер
      // вычисляет его в форме «color(srgb r g b / a)» (слэш), у rgba()
      // был бы «rgba(r, g, b, a)» (запятая) — пробуем оба.
      const числаТениОреола = стильОреола.boxShadow !== 'none'
        ? (стильОреола.boxShadow.match(/-?\d+(\.\d+)?px/g) || []).map(parseFloat)
        : [];
      const альфаТениОреола = стильОреола.boxShadow !== 'none'
        ? (parseFloat((стильОреола.boxShadow.match(/\/\s*([\d.]+)\s*\)/) || [])[1])
          || parseFloat((стильОреола.boxShadow.match(/,\s*([\d.]+)\s*\)/) || [])[1])
          || null)
        : null;
      р.ореолПервогоМеста = {
        boxShadow: стильОреола.boxShadow,
        backgroundImage: стильОреола.backgroundImage,
        width: parseFloat(стильОреола.width) || null,
        blur: числаТениОреола.length >= 3 ? числаТениОреола[2] : null,
        spread: числаТениОреола.length >= 4 ? числаТениОреола[3] : null,
        alpha: альфаТениОреола
      };
    }

    // Шапка (заголовок + кнопка «i»)
    const шапка = экран.querySelector('.рейтинг-шапка') || document.getElementById('рейтинг-шапка');
    р.найдено.шапка = Boolean(шапка);
    if (шапка) {
      const rect = шапка.getBoundingClientRect();
      р.шапкаRect = { top: rect.top, bottom: rect.bottom, left: rect.left, right: rect.right };
    }
    const кнопкаИнфо = document.getElementById('кнопка-рейтинг-инфо');
    р.найдено.кнопкаИнфо = Boolean(кнопкаИнфо) && кнопкаИнфо.textContent.trim() === 'i';

    // Сегмент «Все игроки | Друзья»
    const круг = document.getElementById('рейтинг-круг') || экран.querySelector('.рейтинг-круг');
    р.найдено.круг = Boolean(круг);
    if (круг) {
      const кнопкиКруга = Array.prototype.slice.call(круг.querySelectorAll('[data-круг]'));
      р.найдено.кнопокКруга = кнопкиКруга.length;
      р.текстыКруга = кнопкиКруга.map((к) => к.textContent.trim());
      const активная = кнопкиКруга.find((к) => к.classList.contains('переключатель__вариант--выбран'));
      р.активныйКруг = активная ? активная.getAttribute('data-круг') : null;
    }

    // Заголовок списка «Место / Игрок / Очки»
    const шапкаСписка = экран.querySelector('.рейтинг-строка--шапка');
    р.найдено.шапкаСписка = Boolean(шапкаСписка);
    р.текстШапкиСписка = шапкаСписка ? шапкаСписка.textContent.replace(/\s+/g, ' ').trim() : '';

    // Своя строка (пилюля «Вы») — вне подиума, отдельной строкой списка
    const своиСтроки = Array.prototype.slice.call(экран.querySelectorAll('.рейтинг-строка--я'));
    р.найдено.своихСтрок = своиСтроки.length;
    р.текстСвоейСтроки = своиСтроки[0] ? своиСтроки[0].textContent.replace(/\s+/g, ' ').trim() : '';
    // Недочёт «Е»: своя строка списка на замере ДО прокрутки (scrollTop=0,
    // ровно то состояние, что попадает на снимок) — нужна её геометрия,
    // чтобы сверить с карточкой «Моё место» и нижней полосой вкладок.
    if (своиСтроки[0]) {
      const rectСвоя = своиСтроки[0].getBoundingClientRect();
      р.свояСтрокаRect = { top: rectСвоя.top, bottom: rectСвоя.bottom, left: rectСвоя.left, right: rectСвоя.right };
    }

    // Текст «моё место» / пояснения (для сценария «друзья пусто»)
    const моёМесто = document.getElementById('рейтинг-моё-место');
    р.текстМоёМесто = моёМесто ? моёМесто.textContent.trim() : '';

    // Кнопка «Добавить друга» (только когда друзей нет)
    const кнопки = Array.prototype.slice.call(экран.querySelectorAll('#рейтинг-таблица button'));
    р.найдено.кнопкаДобавитьДруга = кнопки.some((к) => к.textContent.trim() === 'Добавить друга');
    // Жалоба владельца 23.09: геометрия «Добавить друга» и «Мои друзья» —
    // проверяем, что вторая не наезжает на первую и стоит с отступом.
    const узелДобавитьДруга = кнопки.find((к) => к.textContent.trim() === 'Добавить друга');
    if (узелДобавитьДруга) {
      const rect = узелДобавитьДруга.getBoundingClientRect();
      р.кнопкаДобавитьДругаRect = { top: rect.top, bottom: rect.bottom, left: rect.left, right: rect.right };
    }
    const узелМоиДрузья = document.getElementById('кнопка-рейтинг-мои-друзья');
    р.найдено.кнопкаМоиДрузья = Boolean(узелМоиДрузья);
    if (узелМоиДрузья) {
      const rect = узелМоиДрузья.getBoundingClientRect();
      р.кнопкаМоиДрузьяRect = { top: rect.top, bottom: rect.bottom, left: rect.left, right: rect.right };
    }

    // Нижняя полоса вкладок с активной «Рейтинг»
    const nav = экран.querySelector('.нижние-вкладки[data-вкладки="рейтинг"]');
    р.найдено.нижниеВкладки = Boolean(nav);
    if (nav) {
      const активнаяВкладка = nav.querySelector('.нижняя-вкладка--активна');
      р.найдено.активнаяВкладка = Boolean(активнаяВкладка);
      р.текстАктивнойВкладки = активнаяВкладка ? активнаяВкладка.textContent.replace(/\s+/g, ' ').trim() : '';
      const navRect = nav.getBoundingClientRect();
      // left/right — возврат «css-Б2», беда 1: полоса раньше сжималась
      // до 440px и прижималась к левому краю, не закрывая всю ширину
      // окна снизу — проверке нужны обе границы, не только верх/низ.
      р.нижниеВкладкиRect = { top: navRect.top, bottom: navRect.bottom, left: navRect.left, right: navRect.right };
    }

    // Замеры ширины аватаров подиума
    const аватарМеста1 = экран.querySelector('.рейтинг-подиум-карточка[data-место="1"] .рейтинг-подиум-аватар');
    const аватарыМест23 = Array.prototype.slice.call(экран.querySelectorAll('.рейтинг-подиум-карточка[data-место="2"] .рейтинг-подиум-аватар, .рейтинг-подиум-карточка[data-место="3"] .рейтинг-подиум-аватар'));
    р.ширинаАватара1 = аватарМеста1 ? Math.round(аватарМеста1.getBoundingClientRect().width) : null;
    р.ширинаАватара23 = аватарыМест23.map((а) => Math.round(а.getBoundingClientRect().width));

    // Карточка «Моё место» — партия 6, шаг 5 её ОЖИВИЛА: теперь это
    // золотая sticky-карточка снизу экрана, всегда видима (кроме сценария
    // «новичок» без рейтинговых партий, тут не проверяем), не пустой
    // узел с display:none, как было раньше. Rect настоящий, замер полезен —
    // см. новые проверки «низ достижим» / «не закрыт карточкой» ниже
    // (замерыПрокруткиИНиза) и «свояСтрокаRect».
    const моёМестоКарточка = document.getElementById('рейтинг-моё-место');
    if (моёМестоКарточка) {
      const rectМоёМесто = моёМестоКарточка.getBoundingClientRect();
      // left/right — задание штаба «геометрия»: карточка «Моё место»
      // должна помещаться в окно целиком, не только по высоте, но и по
      // ширине (поломка могла бы увести её translate'ом вбок, не только
      // вниз, как «з» ниже).
      р.моёМестоRect = { top: rectМоёМесто.top, bottom: rectМоёМесто.bottom, left: rectМоёМесто.left, right: rectМоёМесто.right };
      // Недочёт «Е»: подложка-затухание над карточкой («::before» —
      // мягкий переход от списка к карточке вместо жёсткого обрыва
      // строки, которую задевает верхний край sticky-карточки).
      const стильЗатухания = window.getComputedStyle(моёМестоКарточка, '::before');
      // Возврат «css-Б2», беда 2: мало знать высоту зоны градиента —
      // нужно понять, накрывает ли она РЕАЛЬНЫЙ ТЕКСТ строки списка,
      // а не пустой зазор над карточкой (прежняя проверка на это не
      // смотрела и не заметила беду). Строка «над карточкой» — та, чей
      // верх лежит выше верха карточки: если их несколько (список
      // длиннее экрана), берём с наибольшим «bottom» — она стоит ближе
      // всего к карточке или уже уходит под неё.
      // Партия css-В, пункт 8: приём сменился на «сплошная подложка +
      // короткий градиент у дальнего края» (как у «.my-dock» в прототипе) —
      // ближняя к карточке строка должна уйти ПОЛНОСТЬЮ (без обрывков
      // букв), а строка ВЫШЕ неё — остаться читаемой целиком (иначе
      // «нет обрывка» пройдёт вырожденно, просто погасив весь список).
      // Поэтому берём ДВЕ строки над карточкой: ближнюю (index 0, её
      // задевает подложка) и контрольную (index 1, следующую вверх по
      // списку) — сортировка по убыванию «bottom» (кто ближе к карточке).
      const всеСтрокиСписка = Array.prototype.slice.call(экран.querySelectorAll('.рейтинг-строка'));
      const строкиНадКарточкой = [];
      всеСтрокиСписка.forEach((строка) => {
        const rectСтроки = строка.getBoundingClientRect();
        if (rectСтроки.top < rectМоёМесто.top) {
          строкиНадКарточкой.push({ строка, top: rectСтроки.top, bottom: rectСтроки.bottom });
        }
      });
      строкиНадКарточкой.sort((a, b) => b.bottom - a.bottom);
      const строкаНадКарточкой = строкиНадКарточкой[0] ? { top: строкиНадКарточкой[0].top, bottom: строкиНадКарточкой[0].bottom } : null;
      const узелСтрокиНадКарточкой = строкиНадКарточкой[0] ? строкиНадКарточкой[0].строка : null;
      const узелКонтрольнойСтроки = строкиНадКарточкой[1] ? строкиНадКарточкой[1].строка : null;
      // Возврат «css-Б2», второй раз: замер «зона накрывает текст» по
      // одной геометрии высоты оказался слеп к реальной видимости —
      // нужны координаты САМОГО ТЕКСТА (не строки-контейнера с её
      // padding), чтобы снаружи прочитать пиксели снимка именно там,
      // где буквы, а не в пустом отступе вокруг них.
      const имяВСтрокеНадКарточкой = узелСтрокиНадКарточкой ? узелСтрокиНадКарточкой.querySelector('.рейтинг-имя') : null;
      const rectИмяНадКарточкой = имяВСтрокеНадКарточкой ? имяВСтрокеНадКарточкой.getBoundingClientRect() : null;
      const имяВКонтрольнойСтроке = узелКонтрольнойСтроки ? узелКонтрольнойСтроки.querySelector('.рейтинг-имя') : null;
      const rectИмяКонтроль = имяВКонтрольнойСтроке ? имяВКонтрольнойСтроке.getBoundingClientRect() : null;
      р.затуханиеНадКарточкой = {
        content: стильЗатухания.content,
        backgroundImage: стильЗатухания.backgroundImage,
        height: parseFloat(стильЗатухания.height) || null,
        строкаНадКарточкой: строкаНадКарточкой,
        текстНадКарточкой: rectИмяНадКарточкой ? {
          left: rectИмяНадКарточкой.left, top: rectИмяНадКарточкой.top, bottom: rectИмяНадКарточкой.bottom
        } : null,
        текстКонтроль: rectИмяКонтроль ? {
          left: rectИмяКонтроль.left, top: rectИмяКонтроль.top, bottom: rectИмяКонтроль.bottom
        } : null
      };
    }

    // Липкая «своя» строка внутри #рейтинг-таблица — замеряется ОТДЕЛЬНОЙ
    // функцией замерыЛипкойСвоейСтроки() ПОСЛЕ скриншота (у неё есть
    // scrollIntoView, а скролл до нужного места не должен портить ни
    // скриншот, ни остальные замеры этой функции — см. вызов ниже по файлу).

    // scrollHeight и clientHeight экрана и документа
    р.экранScrollHeight = экран.scrollHeight;
    р.экранClientHeight = экран.clientHeight;
    р.docScrollHeight = document.documentElement.scrollHeight;
    р.docClientHeight = window.innerHeight;

    // Модель прокрутки (шаг 2, партия 6) — живой overflow-y экрана и
    // списка, и есть ли у самого списка своя прокрутка.
    р.overflowYЭкрана = window.getComputedStyle(экран).overflowY;
    const таблицаДляOverflow = document.getElementById('рейтинг-таблица');
    р.overflowYТаблицы = таблицаДляOverflow ? window.getComputedStyle(таблицаДляOverflow).overflowY : null;
    р.таблицаScrollHeight = таблицаДляOverflow ? таблицаДляOverflow.scrollHeight : null;
    р.таблицаClientHeight = таблицаДляOverflow ? таблицаДляOverflow.clientHeight : null;

    // Узлы движения в таблице
    const узлыДвижения = Array.prototype.slice.call(экран.querySelectorAll('.рейтинг-движение'));
    р.узлыДвижения = узлыДвижения.map((у) => ({
      текст: у.textContent.trim(),
      класс: у.className
    }));
    р.найдено.узлыДвиженияСоСтрелками = узлыДвижения.some((у) => /^[↑↓]/.test(у.textContent));

    return р;
  });
}

// Липкая «своя» строка внутри #рейтинг-таблица (.рейтинг-строка--я,
// последняя, без соседей снизу — именно она «прилипает» к низу через
// position: sticky) — актуальная замена #рейтинг-моё-место. Меряем
// ПОСЛЕ scrollIntoView: на первом кадре (scrollTop=0) строка обрезана
// нижним краем #рейтинг-таблица, и замер без прокрутки не отвечает
// на вопрос «видна ли она целиком, когда игрок до неё долистал».
// Вызывать ТОЛЬКО после того, как сняты скриншот и остальные замеры —
// сама функция листает список и тем самым меняет кадр.
async function замерыЛипкойСвоейСтроки(страница) {
  return страница.evaluate(() => {
    const р = { найденоСвоихСтрокВТаблице: 0, свояСтрокаRect: null, таблицаRect: null };
    const таблицаДляСвоей = document.getElementById('рейтинг-таблица');
    const своиСтрокиВТаблице = таблицаДляСвоей
      ? Array.prototype.slice.call(таблицаДляСвоей.querySelectorAll('.рейтинг-строка--я'))
      : [];
    р.найденоСвоихСтрокВТаблице = своиСтрокиВТаблице.length;
    const свояСтрокаДляПрокрутки = своиСтрокиВТаблице[своиСтрокиВТаблице.length - 1] || null;
    if (свояСтрокаДляПрокрутки) {
      свояСтрокаДляПрокрутки.scrollIntoView({ block: 'end' });
      const rectСтрока = свояСтрокаДляПрокрутки.getBoundingClientRect();
      р.свояСтрокаRect = { top: rectСтрока.top, bottom: rectСтрока.bottom };
    }
    if (таблицаДляСвоей) {
      const rectТабл = таблицаДляСвоей.getBoundingClientRect();
      р.таблицаRect = { top: rectТабл.top, bottom: rectТабл.bottom };
    }
    return р;
  });
}

// Модель прокрутки (шаг 2, партия 6) — «низ достижим» и «карточка не
// закрывает последнюю строку». Прокручивает ЭКРАН (не отдельную строку)
// до дна — меняет кадр, поэтому, как и замерыЛипкойСвоейСтроки, вызывать
// ТОЛЬКО после скриншота и остальных замеров этого кадра.
async function замерыПрокруткиИНиза(страница) {
  return страница.evaluate(() => {
    const р = { экранНайден: false };
    const экран = document.getElementById('экран-рейтинга-игроков');
    if (!экран) return р;
    р.экранНайден = true;

    экран.scrollTop = экран.scrollHeight;

    // «Низ достижим»: последний ВИДИМЫЙ прямой ребёнок экрана (по
    // наибольшему bottom среди offsetParent !== null) не должен уйти
    // ниже верха нижней полосы вкладок. Не завязано на конкретный id —
    // кнопка «Назад» прячется в Telegram (offsetParent null), кнопки
    // «Как считается» отдельным узлом внизу экрана больше нет вовсе
    // (план 8.2, её убрала «убедитьсяЧтоЕстьШторкаИнфо» — тестировщик
    // проверил в браузере 22.09: getElementById возвращает null), поэтому
    // «последний видимый» ищем по факту, а не по жёстко вписанному id.
    const nav = экран.querySelector('.нижние-вкладки');
    р.navTop = nav ? nav.getBoundingClientRect().top : null;

    const видимыеДети = Array.prototype.slice.call(экран.children)
      .filter((д) => д.offsetParent !== null);
    let последнийId = null;
    let последнийBottom = null;
    видимыеДети.forEach((д) => {
      const rect = д.getBoundingClientRect();
      if (последнийBottom === null || rect.bottom > последнийBottom) {
        последнийBottom = rect.bottom;
        последнийId = д.id ? ('#' + д.id) : ('.' + (д.className || '').toString().trim().split(/\s+/)[0]);
      }
    });
    р.последнийВидимыйУзел = последнийId;
    р.последнийВидимыйBottom = последнийBottom;

    // «Карточка не закрывает последнюю строку списка»
    const строки = Array.prototype.slice.call(document.querySelectorAll('.рейтинг-строка'))
      .filter((с) => !с.classList.contains('рейтинг-строка--шапка'));
    const последняяСтрока = строки[строки.length - 1] || null;
    р.последняяСтрокаBottom = последняяСтрока ? последняяСтрока.getBoundingClientRect().bottom : null;

    const карточка = document.getElementById('рейтинг-моё-место');
    р.карточкаВидна = Boolean(карточка) && карточка.offsetParent !== null;
    р.карточкаTop = карточка ? карточка.getBoundingClientRect().top : null;
    // Решение владельца (коммит 07ed072, style.css ~16706-16722): карточка
    // «Моё место» больше не «position: sticky» — идёт ПОСЛЕ списка обычным
    // потоком. Полный rect и вычисленный «position» нужны, чтобы после
    // прокрутки списка до конца проверить это по-настоящему (не только top).
    if (карточка) {
      const rectКарточки = карточка.getBoundingClientRect();
      р.карточкаRect = { top: rectКарточки.top, bottom: rectКарточки.bottom, left: rectКарточки.left, right: rectКарточки.right };
      р.карточкаPosition = window.getComputedStyle(карточка).position;
    } else {
      р.карточкаRect = null;
      р.карточкаPosition = null;
    }

    return р;
  });
}

/* Три проверки решения владельца по карточке «Моё место» (коммит 07ed072,
   style.css ~16706-16722): карточка идёт ПОСЛЕ всего списка обычным
   потоком (не «sticky») и не закрывает его последнюю строку. Проверяем
   ПОСЛЕ прокрутки списка до конца —
     (а) низ карточки не ниже верха полосы вкладок;
     (б) карточка не перекрывает последнюю строку таблицы;
     (в) карточка НЕ «position: sticky».
   При коротком списке карточка может стоять ниже края окна, пока список
   не прокручен, — это ожидаемо и здесь не проверяется (см. образец
   tests/рейтинг-моё-место-не-под-вкладками.js). */
function сверитьКарточкуМоёМестоПослеПрокрутки(проверить, метка, замер, ширинаОкна) {
  const ЗАЗОР = 1;
  if (!замер.карточкаВидна || !замер.карточкаRect) {
    проверить(метка + ' карточка «Моё место» нашлась и видна после прокрутки списка до конца', false,
      'карточкаВидна=' + замер.карточкаВидна);
    return;
  }
  const к = замер.карточкаRect;
  проверить(метка + ' после прокрутки карточка «Моё место» целиком в границах окна по ширине (left≥0, right≤' + ширинаОкна + ')',
    к.left >= -ЗАЗОР && к.right <= ширинаОкна + ЗАЗОР,
    'left=' + Math.round(к.left) + ', right=' + Math.round(к.right));
  проверить(метка + ' (а) низ карточки «Моё место» не ниже верха полосы вкладок',
    замер.navTop === null || к.bottom <= замер.navTop + ЗАЗОР,
    'bottom карточки=' + Math.round(к.bottom) + ', top полосы=' + Math.round(замер.navTop));
  проверить(метка + ' (б) карточка «Моё место» не перекрывает последнюю строку таблицы',
    замер.последняяСтрокаBottom === null || к.top >= замер.последняяСтрокаBottom - ЗАЗОР,
    'top карточки=' + Math.round(к.top) + ', bottom последней строки=' + Math.round(замер.последняяСтрокаBottom));
  проверить(метка + ' (в) карточка «Моё место» не «position: sticky» (решение владельца — обычный поток)',
    замер.карточкаPosition !== 'sticky',
    'position=' + замер.карточкаPosition);
}

