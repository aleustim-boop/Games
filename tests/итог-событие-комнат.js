const г = создать({ игра: 'шашки', имя: 'Аня', телеграм: 7710401 });
const гБот = ход(г.код, г.пропуск, { действие: 'бот' });
сверить(гБот.принято === true, 'Аня посадила бота');
сверить(ход(г.код, г.пропуск, { действие: 'начать' }).принято === true, 'Аня нажала «Начать»');
сверить(место(г.код, г.пропуск).комната.этап === 'игра', 'партия с ботом идёт');
сверить(ход(г.код, г.пропуск, { действие: 'сдаться' }).принято === true, 'Аня сдалась — принято');
const итогГ = забрать('сдача боту → одно «итог»', 1)[0] || null;
const гБ = итогГ ? итогГ.места.find(function (м) { return м.этоБот === true; }) : null;
сверить(Boolean(гБ), 'бот в местах есть (этоБот)');
сверить(Boolean(гБ) && гБ.номер === null && поляРовно(гБ, ПОЛЯ_НЕУЧТЁННОГО),
  'у бота номер пустой, поля «очков» нет: ' + JSON.stringify(гБ));
сверить(Boolean(гБ) && гБ.исход === 'победа', 'у бота исход «победа»');
const гА = поИмени(итогГ, 'Аня');
сверить(Boolean(гА) && гА.исход === 'поражение' && typeof гА.очков === 'number', 'Аня: «поражение», очков — число');
вид(г.код, г.пропуск);
комнаты.удалитьКомнату(г.код);
забрать('уборка уже учтённой партии → итогов 0', 0);

