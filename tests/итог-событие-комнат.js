сверить(дКонец.событие === 'закончена-по-согласию', 'три «за» — партия закончена по согласию (' + дКонец.событие + ')');
const дКомната = место(д.код, д.пропуск).комната;
сверить(дКомната.партия.результат === null, 'результат пустой — рейтинг партию не считал');
