'use strict';
/* =====================================================================
   Постоянная проверка: пары «кто с кем в напарниках» в прихожей должны
   совпадать с парами уже начатой партии. Перенесена из временного
   скрипта разработчика (коммит 739838f, «опись-пары.js» во временной
   папке сессии) в постоянную папку tests/.

   Сервер комнат — модулем, без порта и без записи на диск.

   Запуск:
       node tests/пары-мест-до-и-после-раздачи.js
   Ломающий прогон (проверить, что тест умеет краснеть):
       node tests/пары-мест-до-и-после-раздачи.js --сломать
   «--сломать» подменяет напарника первого игрока на заведомо неверный
   номер (на самого себя — так в паре быть не может) прямо в снятом
   после старта партии виде, не трогая сервер, — и сверка обязана
   заметить подмену.
   ===================================================================== */
const path = require('path');
const комнаты = require(path.join(__dirname, '..', 'server', 'комнаты.js'));
const правила = require(path.join(__dirname, '..', 'js', 'game.js'));
const модель = require(path.join(__dirname, '..', 'js', 'дурак-комната.js')).создать({ правила: правила });

const ЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;
if (ЛОМАТЬ) {
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: напарник первого игрока после раздачи подменяется — проверка обязана покраснеть ***');
}

function вид(код, пропуск) {
  const н = комнаты.найтиИгрока(код, пропуск);
  return комнаты.показатьИгроку(н.комната, н.ктоЯ);
}
function ход(код, пропуск, намерение) {
  const н = комнаты.найтиИгрока(код, пропуск);
  return комнаты.сделатьХод(н.комната, н.ктоЯ, намерение);
}
function пары(в) {
  return в.застолом.map(function (м) { return м.номер + '→' + м.напарник; }).join(' ');
}

/** В ломающем запуске подменяем напарника первого места на заведомо неверный. Иначе — как есть. */
function испортитьЕслиНадо(в) {
  if (!ЛОМАТЬ) return в;
  const испорченный = JSON.parse(JSON.stringify(в));
  if (испорченный.застолом.length) {
    const первый = испорченный.застолом[0];
    первый.напарник = первый.номер;   // сам себе напарник — так по правилам быть не может
  }
  return испорченный;
}

let провалов = 0;
let проверок = 0;
function сверить(имя, до, после) {
  проверок++;
  const да = до === после;
  if (!да) провалов++;
  console.log((да ? 'ок    ' : 'ПЛОХО ') + имя + ': в прихожей [' + до + '], в партии [' + после + ']');
}

// А. Стол на 6 мест парами, сидят 1,2,3,5 (не подряд)
const а = комнаты.создатьКомнату('2.2.2.1', { мест: 6, парами: true, имя: 'Хозяин' });
for (let н = 2; н <= 5; н++) ход(а.код, а.пропуск, { действие: 'бот', место: н });
ход(а.код, а.пропуск, { действие: 'убрать-бота', место: 4 });
const а1 = вид(а.код, а.пропуск);
console.log('6 мест, сидят 1,2,3,5: можноНачать=' + а1.можноНачать + ' пары ' + пары(а1));
console.log('модель, команды: ' + JSON.stringify(модель.собрать(а1).команды));
console.log('начать:', JSON.stringify(ход(а.код, а.пропуск, { действие: 'начать' })));
сверить('6 мест, 1,2,3,5', пары(а1), пары(испортитьЕслиНадо(вид(а.код, а.пропуск))));

// Б. Стол на 4 парами: хозяин + друг, «в напарники», потом два бота, начать
const б = комнаты.создатьКомнату('2.2.2.2', { мест: 4, парами: true, имя: 'Хозяин' });
комнаты.войтиВКомнату(б.код, { имя: 'Друг', метка: 'меткаДруга12345' });
ход(б.код, б.пропуск, { действие: 'в-напарники', кого: 2 });
ход(б.код, б.пропуск, { действие: 'бот', место: 2 });
ход(б.код, б.пропуск, { действие: 'бот', место: 4 });
const б1 = вид(б.код, б.пропуск);
console.log('\n4 места после «в напарники» и двух ботов: пары ' + пары(б1));
console.log('начать:', JSON.stringify(ход(б.код, б.пропуск, { действие: 'начать' })));
сверить('4 места, в-напарники', пары(б1), пары(испортитьЕслиНадо(вид(б.код, б.пропуск))));

console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);
process.exit(провалов ? 1 : 0);
