/* =====================================================================
   ЛОВЕЦ ВЫБЫВШЕЙ ПЛАШКИ — сторож, который сам дожидается редкого экрана.

   ЗАЧЕМ. Плашка выбывшего игрока («отыграл», «играет Бот 4», «играете вы»)
   появляется в живой партии редко: за столом парами нужно, чтобы кто-то
   остался без карт, а партия при этом продолжалась. Ждать её руками —
   это десятки партий подряд. Дизайнер прямо написал, что живьём такой
   плашки не дождался и мерил подстановкой строки.

   ЧТО ДЕЛАЕТ. Смотрит на полосу соперников десять раз в секунду и:
     • копит каждую увиденную выбывшую плашку — что на ней написано,
       какой ширины, не вылезла ли она за экран;
     • сверяет надпись с правилом: за столом ПАРАМИ место выбывшего
       не пустует — за него играет напарник, значит на плашке обязано
       стоять «играет Бот N» или «играете вы». За столом БЕЗ ПАР играть
       за это место некому — там обязано стоять «отыграл»;
     • сам нажимает «Играть ещё» на экране итога и заново пускает
       автоигрока, чтобы партии шли одна за другой без человека;
     • по просьбе замирает на первой же выбывшей плашке — тогда её можно
       спокойно сфотографировать.

   ЧЕГО НЕ ДЕЛАЕТ. Не трогает правила и не лезет внутрь игры: он читает
   ровно то, что видит человек, — надписи на экране.

   КАК ПОЛЬЗОВАТЬСЯ (из консоли браузера, вместе с автоигроком):
       Ловец.начать();               // копить и играть партию за партией
       Ловец.начать({замереть: true});  // остановиться на первой плашке
       Ловец.отчёт();                // что поймано и что не сошлось
       Ловец.стоп();
   ===================================================================== */

(function () {
  'use strict';

  const ШАГ = 100;

  const состояние = {
    работает: false,
    замереть: false,
    поймал: false,
    партий: 0,
    снимков: 0,
    виды: {},        // «что написано» → сколько раз встречено
    расхождения: [], // надпись не сошлась с правилом
    заЭкран: [],     // плашка вылезла за край экрана
    таймер: null
  };

  function эл(id) { return document.getElementById(id); }

  function виден(узел) {
    if (!узел) return false;
    if (узел.classList.contains('скрыт')) return false;
    const р = узел.getBoundingClientRect();
    return р.width > 0 && р.height > 0;
  }

  /** Играем ли мы парами: у моего напарника на плашке своя пометка. */
  function этоПарами() {
    return Boolean(document.querySelector('#соперники .соперник--напарник'));
  }

  /** Разобрать одну плашку на части, которые видит человек. */
  function разобрать(узел) {
    const часть = function (класс) {
      const у = узел.querySelector('.' + класс);
      return у ? (у.textContent || '').trim() : '';
    };
    const р = узел.getBoundingClientRect();
    return {
      имя: часть('соперник__имя'),
      роль: часть('соперник__роль'),
      карт: часть('соперник__карт'),
      метка: часть('соперник__метка'),
      весьТекст: (узел.textContent || '').trim(),
      выбыл: узел.classList.contains('соперник--выбыл'),
      напарник: узел.classList.contains('соперник--напарник'),
      слева: Math.round(р.left),
      справа: Math.round(р.right),
      ширина: Math.round(р.width),
      высота: Math.round(р.height)
    };
  }

  /**
   * Кто напарник этого места за парным столом. Мест четыре, свои сидят
   * через одного: 1-3 и 2-4. Плашек на экране три (себя человек видит
   * своей рукой), поэтому напарника ищем по номеру в имени.
   */
  /**
   * ПРАВДА о столе: кто где сидит, кто с кем в паре, кто уже вышел.
   *
   * Читаем её изнутри игры, а не с экрана, — и вот почему. Надпись мы
   * по-прежнему берём с экрана, но чтобы её судить, надо знать, кто чей
   * напарник. По экрану это не узнать в двух случаях сразу: своей плашки
   * человек не видит вовсе, а за сетевым столом имена у людей любые
   * («Александра-Мария»), и номер кресла из имени не вычитать.
   *
   * Возвращаем один и тот же вид для обоих столов: список мест, у каждого
   * номер кресла, имя (так, как его пишет игра), «это я», «вышел»
   * и номер кресла напарника.
   */
  function правдаОСтоле() {
    let п = null;
    try { п = (0, eval)('typeof партия !== "undefined" ? партия : null'); } catch (е) { п = null; }
    if (!п) return null;

    // Сетевой стол: список мест целиком присылает сервер.
    if (Array.isArray(п.застолом)) {
      return {
        парами: п.парами === true,
        места: п.застолом.map(function (м) {
          return { номер: м.номер, имя: м.имя, этоЯ: m_этоЯ(м), вышел: м.выбыл === true, напарник: м.напарник || null };
        })
      };
    }

    // Стол с ботами: места считаем сами, свои сидят через одного.
    if (!Array.isArray(п.игроки)) return null;
    const выбывшие = п.выбывшие || [];
    return {
      парами: п.парами === true,
      места: п.игроки.map(function (ключ, i) {
        return {
          номер: i + 1,
          имя: ключ === 'человек' ? 'Вы' : 'Бот ' + (i + 1),
          этоЯ: ключ === 'человек',
          вышел: выбывшие.indexOf(ключ) !== -1,
          напарник: п.парами === true ? ((i + 2) % п.игроки.length) + 1 : null
        };
      })
    };
  }

  function m_этоЯ(м) { return м.этоЯ === true; }

  /** Что ДОЛЖНО быть написано на плашке этого выбывшего места. */
  function ожидаемаяНадпись(правда, место) {
    if (!правда || !правда.парами || !место.напарник) return 'отыграл';
    const нап = правда.места.filter(function (м) { return м.номер === место.напарник; })[0];
    if (!нап || нап.вышел) return 'отыграл';
    return нап.этоЯ ? 'играете вы' : 'играет ' + нап.имя;
  }

  function проверить(плашки, парами) {
    const правда = правдаОСтоле();
    for (const п of плашки) {
      if (!п.выбыл) continue;
      состояние.снимков++;
      const ключ = (парами ? 'парами' : 'без пар') + ' | ' + п.имя + ' | «' + п.метка +
        '» | карт: «' + п.карт + '»' + (п.роль ? ' | роль: «' + п.роль + '»' : '');
      состояние.виды[ключ] = (состояние.виды[ключ] || 0) + 1;

      // Плашка обязана помещаться в экран.
      if (п.слева < 0 || п.справа > window.innerWidth) {
        const беда = 'плашка «' + п.имя + '» вылезла за экран: слева ' + п.слева +
          ', справа ' + п.справа + ' при ширине окна ' + window.innerWidth;
        if (состояние.заЭкран.indexOf(беда) === -1) состояние.заЭкран.push(беда);
      }

      /* Надпись против правила. Плашку на экране узнаём по имени: имена
         за столом не повторяются ни у ботов, ни у людей. */
      const местоВПравде = правда
        ? правда.места.filter(function (м) { return м.имя === п.имя; })[0]
        : null;
      if (!местоВПравде) continue;      // не с чем сверять — молчим, а не выдумываем
      const ожидание = ожидаемаяНадпись(правда, местоВПравде);
      if (п.метка !== ожидание) {
        const беда = (парами ? 'парами' : 'без пар') + ': на плашке «' + п.имя +
          '» написано «' + п.метка + '», а по правилам должно быть «' + ожидание + '»' +
          ' (весь текст плашки: «' + п.весьТекст + '»; вышли из игры: ' +
          (правда ? (правда.места.filter(function (м) { return м.вышел; })
            .map(function (м) { return м.имя; }).join(', ') || 'никто') : 'неизвестно') + ')';
        if (состояние.расхождения.indexOf(беда) === -1) состояние.расхождения.push(беда);
      }

      состояние.поймал = true;
      if (состояние.замереть) {
        if (window.Автоигрок) window.Автоигрок.стоп();
        состояние.работает = false;
      }
    }
  }

  function шаг() {
    if (!состояние.работает) return;
    try {
      // Партия кончилась — начинаем следующую, чтобы ждать плашку дальше.
      if (виден(эл('экран-результата'))) {
        состояние.партий++;
        const ещё = эл('кнопка-ещё');
        if (ещё) ещё.click();
        setTimeout(function () {
          if (window.Автоигрок && состояние.работает) window.Автоигрок.начать(0.6, true, 0);
        }, 400);
      } else if (виден(эл('экран-игры'))) {
        const плашки = [].map.call(document.querySelectorAll('#соперники .соперник'), разобрать);
        if (плашки.length) проверить(плашки, этоПарами());
        // Автоигрок мог сам остановиться (например, доиграл) — поднимаем его.
        if (window.Автоигрок && !window.Автоигрок.работает() && состояние.работает) {
          window.Автоигрок.начать(0.6, true, 0);
        }
      }
    } catch (е) {
      состояние.расхождения.push('ловец споткнулся: ' + е);
    }
    if (состояние.работает) состояние.таймер = setTimeout(шаг, ШАГ);
  }

  window.Ловец = {
    начать: function (настройки) {
      состояние.замереть = Boolean(настройки && настройки.замереть);
      состояние.работает = true;
      состояние.поймал = false;
      состояние.таймер = setTimeout(шаг, ШАГ);
      return 'слежу за полосой соперников';
    },
    стоп: function () {
      состояние.работает = false;
      if (состояние.таймер) clearTimeout(состояние.таймер);
      return 'остановился';
    },
    поймал: function () { return состояние.поймал; },
    отчёт: function () {
      return {
        партийСыграно: состояние.партий,
        снимковВыбывшихПлашек: состояние.снимков,
        видыНадписей: состояние.виды,
        расхождения: состояние.расхождения,
        заЭкран: состояние.заЭкран,
        работает: состояние.работает
      };
    }
  };
})();
