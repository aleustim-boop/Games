/* =====================================================================
   Помощники для проверки игры руками, прямо в браузере.

   Это НЕ часть игры и не автотест. Это набор из четырёх кнопок-функций,
   которыми тестировщик проверял вёрстку и цвета. Ими же штаб может
   повторить любую находку из отчёта.

   КАК ПОЛЬЗОВАТЬСЯ
     1. Запустите сервер:      node tests/локальный-сервер.js 8123
     2. Откройте в браузере:   http://localhost:8123/index.html?v=7
     3. Откройте консоль браузера (F12 → вкладка Console).
     4. Скопируйте ВЕСЬ этот файл и вставьте в консоль, нажмите Enter.
     5. Нажмите в игре «Играть» и пользуйтесь командами ниже.

   ЧТО МОЖНО НАБИРАТЬ В КОНСОЛИ

     стенд(18, 6, 6)     — разложить тяжёлый расклад: 18 карт в руке,
                           6 пар на столе, все шесть побиты.
                           стенд(35, 0, 0) — предельная рука в 35 карт.
     вылезло()           — обойти всё видимое и сказать, что уехало
                           за край экрана или обрезалось.
     контраст()          — посчитать читаемость каждой надписи.
                           Меньше 4,5 для мелкого текста — плохо.
     тема('светлая')     — включить цвета светлой темы Telegram.
     тема('тёмная')      — цвета тёмной темы.
     тема('своя')        — вернуть родное «зелёное сукно» игры.

   Размер окна меняется средствами браузера (F12 → режим телефона).
   Проверяли на 390×844, 390×420, 320×568, 280×640 и в повороте 844×390.
   ===================================================================== */

(function () {
  'use strict';

  /* ------------------------------------------------------------------
     Тяжёлый расклад прямо в живой партии
     ------------------------------------------------------------------ */

  window.стенд = function (картВРуке, пар, изНихПобито) {
    if (typeof партия === 'undefined' || !партия) {
      console.log('Сначала нажмите «Играть» — стенд подменяет карты в идущей партии.');
      return;
    }
    const все = собратьКолоду();       // ♠6..♠Т, ♥6..♥Т, ♦6..♦Т, ♣6..♣Т
    партия.козырь = '♣';
    партия.козырнаяКарта = все[все.length - 1];

    let i = 0;
    партия.руки.человек = все.slice(0, картВРуке);
    i = картВРуке;

    партия.стол = [];
    for (let п = 0; п < пар; п++) {
      const атака = все[i++];
      const защита = п < изНихПобито ? все[i++] : null;
      партия.стол.push({ атака: атака, защита: защита });
    }

    партия.руки.бот = все.slice(i, Math.min(i + 6, все.length));
    i = Math.min(i + 6, все.length);
    партия.колода = все.slice(i);
    партия.отбой = [];
    партия.берёт = false;
    партия.завершена = false;
    партия.результат = null;
    партия.атакует = 'человек';
    выбраннаяКарта = null;
    убратьСобытие();
    подобратьРазмерКарты();
    перерисовать();
    console.log('Разложено: в руке ' + партия.руки.человек.length +
                ', пар на столе ' + партия.стол.length + ', у соперника ' + партия.руки.бот.length);
  };

  /* ------------------------------------------------------------------
     Что уехало за экран или обрезалось
     ------------------------------------------------------------------ */

  /** Лежит ли элемент внутри блока, который можно прокрутить (тогда он достижим). */
  function вПрокрутке(узел) {
    let родитель = узел.parentElement;
    while (родитель && родитель !== document.body) {
      if (родитель.scrollHeight > родитель.clientHeight + 2 ||
          родитель.scrollWidth > родитель.clientWidth + 2) return true;
      родитель = родитель.parentElement;
    }
    return false;
  }

  function имя(узел) {
    const текст = (узел.textContent || '').trim();
    return (узел.id ? '#' + узел.id : (узел.className || узел.tagName)) +
           (текст && текст.length < 40 ? ' «' + текст + '»' : '');
  }

  window.вылезло = function () {
    const Ш = window.innerWidth, В = window.innerHeight;
    const заЭкран = [], обрезано = [];

    document.querySelectorAll('.экран--виден, .экран--виден *').forEach(function (узел) {
      const с = getComputedStyle(узел);
      if (с.display === 'none' || с.visibility === 'hidden' || Number(с.opacity) === 0) return;
      const р = узел.getBoundingClientRect();
      if (р.width === 0 && р.height === 0) return;
      if (вПрокрутке(узел)) return;         // до него можно доскроллить — это не беда
      if (р.left < -1) заЭкран.push(имя(узел) + ' — за левый край на ' + Math.round(-р.left) + 'px');
      if (р.right > Ш + 1) заЭкран.push(имя(узел) + ' — за правый край на ' + Math.round(р.right - Ш) + 'px');
      if (р.top < -1) заЭкран.push(имя(узел) + ' — выше экрана на ' + Math.round(-р.top) + 'px');
      if (р.bottom > В + 1) заЭкран.push(имя(узел) + ' — ниже экрана на ' + Math.round(р.bottom - В) + 'px');
    });

    document.querySelectorAll('.экран--виден *').forEach(function (узел) {
      if (узел.children.length) return;
      if (узел.closest('.карта')) return;   // цифру и масть на карте смотрим глазами
      if (!(узел.textContent || '').trim()) return;
      // Запас в 3 пикселя — на межстрочный интервал, он не считается обрезкой.
      if (узел.scrollWidth > узел.clientWidth + 3 || узел.scrollHeight > узел.clientHeight + 3) {
        обрезано.push(имя(узел) + ' (место ' + узел.clientWidth + 'x' + узел.clientHeight +
                      ', надо ' + узел.scrollWidth + 'x' + узел.scrollHeight + ')');
      }
    });

    const итог = {
      окно: Ш + 'x' + В,
      уехалоЗаЭкран: заЭкран,
      обрезанныйТекст: обрезано,
      прокруткаСтраницы: document.documentElement.scrollWidth > Ш + 1 ||
                         document.documentElement.scrollHeight > В + 1
    };
    if (!заЭкран.length && !обрезано.length && !итог.прокруткаСтраницы) {
      console.log('Окно ' + итог.окно + ': всё внутри экрана, ничего не обрезано.');
    }
    return итог;
  };

  /* ------------------------------------------------------------------
     Читаемость надписей (контраст по формуле W3C)
     ------------------------------------------------------------------ */

  const холст = document.createElement('canvas');
  холст.width = холст.height = 1;
  const кисть = холст.getContext('2d', { willReadFrequently: true });

  /** Любую запись цвета (в том числе color-mix) превращаем в числа. */
  function вЧисла(цвет) {
    кисть.clearRect(0, 0, 1, 1);
    кисть.fillStyle = 'rgba(0,0,0,0)';
    кисть.fillStyle = цвет;
    кисть.fillRect(0, 0, 1, 1);
    const т = кисть.getImageData(0, 0, 1, 1).data;
    return { r: т[0], g: т[1], b: т[2], a: т[3] / 255 };
  }

  function яркость(ц) {
    const f = function (в) { в /= 255; return в <= 0.03928 ? в / 12.92 : Math.pow((в + 0.055) / 1.055, 2.4); };
    return 0.2126 * f(ц.r) + 0.7152 * f(ц.g) + 0.0722 * f(ц.b);
  }

  /** Полупрозрачный цвет поверх непрозрачного. */
  function поверх(верх, низ) {
    const a = верх.a;
    return { r: верх.r * a + низ.r * (1 - a), g: верх.g * a + низ.g * (1 - a),
             b: верх.b * a + низ.b * (1 - a), a: 1 };
  }

  window.контраст = function () {
    const строки = [];
    document.querySelectorAll('.экран--виден *').forEach(function (узел) {
      if (узел.children.length) return;
      const текст = (узел.textContent || '').trim();
      if (!текст || узел.closest('.карта')) return;
      const с = getComputedStyle(узел);
      if (с.display === 'none' || с.visibility === 'hidden' || Number(с.opacity) === 0) return;

      const цвет = вЧисла(с.color);
      // Собираем фон: идём вверх, пока не встретим непрозрачную подложку.
      const слои = [];
      let текущий = узел, нашли = false;
      while (текущий) {
        const ф = вЧисла(getComputedStyle(текущий).backgroundColor);
        if (ф.a > 0) слои.push(ф);
        if (ф.a === 1) { нашли = true; break; }
        текущий = текущий.parentElement;
      }
      let фон = нашли ? слои.pop() : { r: 255, g: 255, b: 255, a: 1 };
      for (let i = слои.length - 1; i >= 0; i--) фон = поверх(слои[i], фон);

      const светлее = Math.max(яркость(поверх(цвет, фон)), яркость(фон));
      const темнее = Math.min(яркость(поверх(цвет, фон)), яркость(фон));
      строки.push({ надпись: текст.slice(0, 40),
                    контраст: Math.round((светлее + 0.05) / (темнее + 0.05) * 10) / 10,
                    размер: с.fontSize });
    });
    строки.sort(function (а, б) { return а.контраст - б.контраст; });
    const плохие = строки.filter(function (с) { return с.контраст < 4.5; });
    console.log(плохие.length === 0
      ? 'Все надписи читаются: контраст не ниже 4,5.'
      : 'Ниже нормы 4,5: ' + плохие.length + ' надписей (см. начало списка).');
    return строки;
  };

  /* ------------------------------------------------------------------
     Цвета тем Telegram
     ------------------------------------------------------------------ */

  const ТЕМЫ = {
    'светлая': { 'bg-color': '#ffffff', 'text-color': '#000000', 'hint-color': '#999999',
                 'button-color': '#2481cc', 'button-text-color': '#ffffff', 'secondary-bg-color': '#f1f1f1' },
    'тёмная':  { 'bg-color': '#17212b', 'text-color': '#ffffff', 'hint-color': '#708499',
                 'button-color': '#5288c1', 'button-text-color': '#ffffff', 'secondary-bg-color': '#232e3c' }
  };

  window.тема = function (какая) {
    const стиль = document.documentElement.style;
    const ключи = ['bg-color', 'text-color', 'hint-color', 'button-color',
                   'button-text-color', 'secondary-bg-color'];
    ключи.forEach(function (к) { стиль.removeProperty('--tg-theme-' + к); });
    if (ТЕМЫ[какая]) {
      ключи.forEach(function (к) { стиль.setProperty('--tg-theme-' + к, ТЕМЫ[какая][к]); });
      console.log('Включена ' + какая + ' тема Telegram.');
    } else {
      console.log('Вернул родные цвета игры (зелёное сукно).');
    }
  };

  console.log('Помощники готовы. Команды: стенд(18,6,6) · вылезло() · контраст() · ' +
              "тема('светлая') · тема('тёмная') · тема('своя')");
})();
