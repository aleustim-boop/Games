'use strict';

/* =====================================================================
   ПРИСУТСТВИЕ (server/присутствие.js) — без сети и без настоящего сервера.

   Что это за модуль. Он помнит, кто из игроков только что стучался
   в приложение («на связи»), и отдельно — кто нажал «не показывать меня
   друзьям» («прячусь»). Первое живёт только в памяти и пропадает при
   перезапуске сервера нарочно, второе обязано пережить перезапуск,
   потому что это решение человека.

   Что проверяем этим файлом (без браузера и без сети — только вызовы
   функций модуля напрямую):
     1) отметили троих — наСвязиИзСписка видит всех троих;
     2) спросили и про того, кого не отмечали, — его в ответе нет;
     3) наружу отдаются ТОЛЬКО номера, про которые спросили (это и есть
        приватность модуля — весь список присутствия наружу не течёт);
     4) номер-число и номер-строка находят одну и ту же запись (если
        где-то разойдётся — это честная находка, а не повод подогнать
        проверку под неожиданный результат);
     5) время жизни присутствия можно подменить на 50 мс — после паузы
        длиннее этого срока человек с «на связи» пропадает;
     6) «прячусь» прячет из наСвязиИзСписка, снятие «прячусь» возвращает
        обратно, прячетсяЛи сообщает точно то же самое;
     7) «прячусь» пишется на диск и переживает перезагрузку модуля
        (require.cache очищен и модуль подключён заново с диска),
        а присутствие (память) после такой перезагрузки пустое;
     8) мусорный ввод — null, undefined, голый объект, логическое true,
        имя в 10000 символов — не роняет процесс исключением и не
        оседает записью там, где не должен (имя обрезается до 32 знаков,
        а не хранится целиком);
     9) потолок в 20000 записей: 20001-я отметка не даёт счётчику
        сколькоНаСвязи перевалить за потолок.

   ЛОМАЮЩИЙ ЗАПУСК (обязан покраснеть):
       node tests/присутствие.js --корень=<путь до копии server/>
   Путь ведёт на ПОРЧЕНУЮ копию server/ — присутствие.js в ней должен
   отдавать наСвязиИзСписка прячущихся людей как обычных (например,
   выключена строчка «if (прячущиеся.has(кого)) continue;»), плюс рядом
   должен лежать нетронутый server/папка-данных.js (его требует
   присутствие.js через require('./папка-данных.js')). Проверка обязана
   упасть на сценарии 6. Копию готовит и портит тот, кто проводит
   ломающий запуск — сам этот файл ничего не портит и не трогает
   ничего за пределами своей временной папки данных.

   Обычный запуск:
       node tests/присутствие.js
   ===================================================================== */

const path = require('path');
const os = require('os');
const fs = require('fs');

const КОРЕНЬ_ПРОЕКТА = path.join(__dirname, '..');

const аргКорень = process.argv.find(function (а) { return а.startsWith('--корень='); });
const ПАПКА_СЕРВЕРА = аргКорень ? аргКорень.slice('--корень='.length) : path.join(КОРЕНЬ_ПРОЕКТА, 'server');

/* Своя временная папка данных — переменную ставим ДО require модуля,
   иначе первое же обращение к папке данных (например, при отметить
   с включённой записью) могло бы задеть боевые файлы. Удаляем ТОЛЬКО
   эту папку и только при выходе процесса. */
const ПАПКА_ДАННЫХ = path.join(os.tmpdir(), 'присутствие-проверка-данные-' + process.pid + '-' + Date.now());
process.env.ДАННЫЕ_ИГРЫ = ПАПКА_ДАННЫХ;

process.on('exit', function () {
  try { fs.rmSync(ПАПКА_ДАННЫХ, { recursive: true, force: true }); } catch (е) { /* временная папка необязательна */ }
});

let проверок = 0;
let провалов = 0;
function зелёный(текст) { проверок++; console.log('  ок — ' + текст); }
function красный(текст) { проверок++; провалов++; console.log('  ПРОВАЛ — ' + текст); }
function проверить(условие, текст) { if (условие) зелёный(текст); else красный(текст); }
function пауза(мс) { return new Promise(function (готово) { setTimeout(готово, мс); }); }

/** Человеческое описание мусорного значения для текста находки. */
function опишиМусор(значение) {
  if (значение === null) return 'null';
  if (значение === undefined) return 'undefined';
  if (Array.isArray(значение)) return '[] (пустой массив)';
  if (typeof значение === 'object') return '{} (голый объект)';
  return typeof значение + ' ' + String(значение);
}

const ПУТЬ_МОДУЛЯ = path.resolve(path.join(ПАПКА_СЕРВЕРА, 'присутствие.js'));

async function основной() {
  let присутствие = require(ПУТЬ_МОДУЛЯ);

  /* ===================================================================
     1) отметили троих — видно троих.
     =================================================================== */
  присутствие.забытьВсё();
  const А = 700000001, Б = 700000002, В = 700000003, Г = 700000004;
  присутствие.отметить(А, 'Аня');
  присутствие.отметить(Б, 'Боря');
  присутствие.отметить(В, 'Вера');
  const трое = присутствие.наСвязиИзСписка([А, Б, В]);
  проверить(трое.size === 3 && трое.has(А) && трое.has(Б) && трое.has(В),
    '1) отметили троих — наСвязиИзСписка видит всех троих (получили ' + трое.size + ')');

  /* ===================================================================
     2) спросили и про не отмеченного — его в ответе нет.
     =================================================================== */
  const сЧетвёртым = присутствие.наСвязиИзСписка([А, Б, В, Г]);
  проверить(!сЧетвёртым.has(Г) && сЧетвёртым.size === 3,
    '2) не отмеченного (Г) в списке нет, остальные три на месте (получили ' + сЧетвёртым.size + ')');

  /* ===================================================================
     3) наружу только те номера, про которые спросили.
     =================================================================== */
  const толькоА = присутствие.наСвязиИзСписка([А]);
  проверить(толькоА.size === 1 && толькоА.has(А) && !толькоА.has(Б) && !толькоА.has(В),
    '3) спросили только про А (хотя на связи ещё Б и В) — в ответе только А (получили номера: ' +
    Array.from(толькоА.keys()).join(',') + ')');

  /* ===================================================================
     4) номер числом и номер строкой находятся одинаково.
     =================================================================== */
  присутствие.забытьВсё();
  const Д = 700000005, Е = 700000006;
  присутствие.отметить(Д, 'Числом');
  const поСтроке = присутствие.наСвязиИзСписка([String(Д)]);
  проверить(поСтроке.size === 1 && поСтроке.has(Д),
    '4а) отметили номером-числом ' + Д + ', спросили строкой "' + Д + '" — нашли (получили size=' + поСтроке.size + ')');

  присутствие.отметить(String(Е), 'Строкой');
  const почислу = присутствие.наСвязиИзСписка([Е]);
  проверить(почислу.has(Е),
    '4б) отметили номером-строкой "' + Е + '", спросили числом ' + Е + ' — нашли (получили has=' + почислу.has(Е) + ')');

  присутствие.прятаться(String(Д), true);
  проверить(присутствие.прячетсяЛи(Д) === true,
    '4в) спрятались, передав номер строкой — прячетсяЛи с номером-числом видит скрытность');
  присутствие.прятаться(Д, false); // снимаем, чтобы не мешало дальше

  /* ===================================================================
     5) время жизни присутствия 50 мс — после ожидания дольше него ноль.
     =================================================================== */
  присутствие.подменитьВремяЖизниДляПроверки(50);
  присутствие.забытьВсё();
  присутствие.отметить(700000007, 'Скороход');
  проверить(присутствие.сколькоНаСвязи() === 1, '5) сразу после отметки на связи один человек');
  await пауза(120);
  проверить(присутствие.сколькоНаСвязи() === 0,
    '5) время жизни подменили на 50 мс, подождали 120 мс — на связи никого не осталось (получили ' +
    присутствие.сколькоНаСвязи() + ')');
  присутствие.подменитьВремяЖизниДляПроверки(); // вернуть обычные 90 секунд для дальнейших сценариев

  /* ===================================================================
     6) «прячусь» скрывает, снятие возвращает.
     =================================================================== */
  присутствие.забытьВсё();
  const Ж = 700000008;
  присутствие.отметить(Ж, 'Прячется');
  проверить(присутствие.наСвязиИзСписка([Ж]).has(Ж), '6) до пряток человек виден в списке');
  проверить(присутствие.прячетсяЛи(Ж) === false, '6) до пряток прячетсяЛи говорит «нет»');

  присутствие.прятаться(Ж, true);
  проверить(!присутствие.наСвязиИзСписка([Ж]).has(Ж), '6) после «прячусь» человека в наСвязиИзСписка нет');
  проверить(присутствие.прячетсяЛи(Ж) === true, '6) прячетсяЛи подтверждает скрытность');

  присутствие.прятаться(Ж, false);
  проверить(присутствие.наСвязиИзСписка([Ж]).has(Ж), '6) сняли «прячусь» — человек снова виден в наСвязиИзСписка');
  проверить(присутствие.прячетсяЛи(Ж) === false, '6) прячетсяЛи подтверждает, что скрытность снята');

  /* ===================================================================
     7) «прячусь» переживает перезагрузку модуля с диска, присутствие —
        нет. Форсируем запись через дописать(), не ждём 5 секунд.
     =================================================================== */
  присутствие.включитьЗапись();
  присутствие.забытьВсё();
  const З = 700000009, И = 700000010;
  присутствие.отметить(З, 'НеПереживёт'); // присутствие — только в памяти
  присутствие.прятаться(И, true);          // прячущиеся — пишутся на диск
  присутствие.дописать();                  // форсируем запись прямо сейчас

  const файлПрячущихся = присутствие.ФАЙЛ;
  проверить(fs.existsSync(файлПрячущихся), '7) файл прячущихся реально появился на диске: ' + файлПрячущихся);

  delete require.cache[ПУТЬ_МОДУЛЯ];
  const присутствиеЗаново = require(ПУТЬ_МОДУЛЯ);
  проверить(присутствиеЗаново.прячетсяЛи(И) === true,
    '7) после перезагрузки модуля с диска (require.cache очищен) «прячусь» для И пережило перезапуск');
  проверить(присутствиеЗаново.сколькоНаСвязи() === 0,
    '7) присутствие (память) не пережило перезагрузку модуля — сколькоНаСвязи=0 (получили ' +
    присутствиеЗаново.сколькоНаСвязи() + ')');
  присутствие = присутствиеЗаново;

  /* ===================================================================
     8) мусорный ввод не роняет процесс и не записывается.
     =================================================================== */
  присутствие.подменитьВремяЖизниДляПроверки();
  присутствие.забытьВсё();
  const мусорныеНомера = [null, undefined, {}, [], NaN, -5, 1.5, '   ', true];
  for (const плохой of мусорныеНомера) {
    try {
      const рез = присутствие.отметить(плохой, 'Мусор');
      проверить(рез === false, '8) отметить(' + опишиМусор(плохой) + ', "Мусор") не создал запись, вернул false');
    } catch (беда) {
      красный('8) отметить(' + опишиМусор(плохой) + ') бросил исключение вместо того, чтобы вернуть false: ' + беда.message);
    }
    try {
      const рез2 = присутствие.прятаться(плохой, true);
      проверить(рез2 === false, '8) прятаться(' + опишиМусор(плохой) + ', true) не создал запись, вернул false');
    } catch (беда) {
      красный('8) прятаться(' + опишиМусор(плохой) + ') бросил исключение вместо того, чтобы вернуть false: ' + беда.message);
    }
  }
  проверить(присутствие.сколькоНаСвязи() === 0,
    '8) после всех мусорных вызовов присутствие по-прежнему пустое (получили ' + присутствие.сколькоНаСвязи() + ')');

  try {
    const наНичто1 = присутствие.наСвязиИзСписка(null);
    проверить(наНичто1.size === 0, '8) наСвязиИзСписка(null) — пустой список, не падает');
  } catch (беда) {
    красный('8) наСвязиИзСписка(null) бросил исключение: ' + беда.message);
  }
  try {
    const наНичто2 = присутствие.наСвязиИзСписка(undefined);
    проверить(наНичто2.size === 0, '8) наСвязиИзСписка(undefined) — пустой список, не падает');
  } catch (беда) {
    красный('8) наСвязиИзСписка(undefined) бросил исключение: ' + беда.message);
  }
  try {
    const наОбъект = присутствие.наСвязиИзСписка({});
    проверить(наОбъект.size === 0, '8) наСвязиИзСписка({}) — голый объект вместо списка не падает, пустой список');
  } catch (беда) {
    красный('8) наСвязиИзСписка({}) — голый объект вместо списка НОМЕРОВ бросил исключение: ' + беда.message +
      ' (находка: модуль ждёт итерируемый список и не проверяет это заранее)');
  }

  // мусорное ИМЯ при валидном номере — не роняет, не хранится целиком
  const МК = 700000011;
  присутствие.отметить(МК, 'и'.repeat(10000));
  const сДлиннымИменем = присутствие.наСвязиИзСписка([МК]);
  const имяДлинное = сДлиннымИменем.has(МК) ? сДлиннымИменем.get(МК).имя : null;
  проверить(сДлиннымИменем.has(МК) && typeof имяДлинное === 'string' && имяДлинное.length <= 32,
    '8) имя в 10000 символов не уронило процесс, в памяти обрезано до ' +
    (имяДлинное === null ? 'null' : имяДлинное.length) + ' символов');

  присутствие.отметить(700000012, {});
  const сОбъектомВместоИмени = присутствие.наСвязиИзСписка([700000012]).get(700000012);
  проверить(сОбъектомВместоИмени && сОбъектомВместоИмени.имя === '',
    '8) объект вместо имени не роняет — имя стало пустой строкой (получили ' +
    JSON.stringify(сОбъектомВместоИмени && сОбъектомВместоИмени.имя) + ')');

  /* ===================================================================
     9) потолок: 20001-я отметка — сколькоНаСвязи не превышает 20000.
     =================================================================== */
  присутствие.подменитьВремяЖизниДляПроверки(); // обычные 90 секунд — никто не должен протухнуть по времени
  присутствие.забытьВсё();
  const ПОТОЛОК_ПРОВЕРКИ = 20001;
  for (let счёт = 1; счёт <= ПОТОЛОК_ПРОВЕРКИ; счёт++) {
    присутствие.отметить(800000000 + счёт, 'Т' + счёт);
  }
  const итогоНаСвязи = присутствие.сколькоНаСвязи();
  проверить(итогоНаСвязи <= 20000,
    '9) отметили ' + ПОТОЛОК_ПРОВЕРКИ + ' раз подряд — сколькоНаСвязи не превысило потолок 20000 (получили ' +
    итогоНаСвязи + ')');
}

основной()
  .catch(function (беда) {
    красный('проверка оборвалась: ' + беда.message);
    console.log(беда.stack);
  })
  .then(function () {
    console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
    process.exit(провалов > 0 ? 1 : 0);
  });
