'use strict';

/* =====================================================================
   ПРОВЕРКА «РЕЙТИНГ — МОЁ МЕСТО БЕЗ ДЕФИСА» (js/рейтинг-экран.js)

   Решение владельца 26.09 («рейтинг-дефис»): в карточке «Моё место» знак
   движения ставим, только когда есть настоящая стрелка (место выросло
   или упало). «—» от «без изменений»/«нет данных» в этой карточке лишний —
   там нет колонки, которую надо выравнивать, как в таблице.

   ЧТО ПРОВЕРЯЕМ (функция заполнитьКарточкуМоегоМеста):
     1) движение «безИзменений» — в карточке «Моё место» узла .рейтинг-движение
        нет вовсе (не пустая приглушённая метка, а именно отсутствие узла);
     2) движение «нетДанных» — то же самое, узла нет;
     3) движение «выросло» на 3 — в карточке есть «↑ 3» как и раньше;
     4) движение «упало» на 2 — в карточке есть «↓ 2» как и раньше;
     5) строка ТАБЛИЦЫ (не «я») с «безИзменений» по-прежнему держит «—»
        (там колонку выравнивать надо, эту правку туда не тащим).

   Узел движения (функция «узелДвижения») не менялся — правка только в
   заполнитьКарточкуМоегоМеста: узел с классом «рейтинг-движение--нет»
   в карточку больше не кладём.

   УМЕЕТ ЛИ ОНА КРАСНЕТЬ.
     --сломать берёт временную копию js/рейтинг-экран.js и возвращает
     старое поведение (узел движения кладётся в карточку всегда, если он
     есть) — пункты 1 и 2 обязаны провалиться: дефис в карточке вернётся.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const бр = require(path.join(__dirname, 'поддельный-браузер.js'));

const КОРЕНЬ = path.join(__dirname, '..');
const файлРейтинга = path.join(КОРЕНЬ, 'js', 'рейтинг-экран.js');
const исходник = fs.readFileSync(файлРейтинга, 'utf8');

const СЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;

/** Заменить в тексте искомый кусок на порченный — только если он реально
    нашёлся (иначе приём порчи устарел вместе с устройством файла, и
    молчать об этом нельзя). */
function испортитьКопию(текст, искомое, замена) {
  if (текст.indexOf(искомое) === -1) {
    console.log('ОШИБКА: приём порчи --сломать устарел — искомая строка не нашлась в ' + файлРейтинга + ':');
    console.log('  ' + искомое);
    process.exit(1);
  }
  return текст.split(искомое).join(замена);
}

let рабочийИсходник = исходник;
if (СЛОМАТЬ) {
  рабочийИсходник = испортитьКопию(исходник,
    "    const движение = узелДвижения(данные);\n" +
    "    if (движение && !движение.classList.contains('рейтинг-движение--нет')) {\n" +
    "      очкиЯчейка.appendChild(движение);\n" +
    "    }",
    "    const движение = узелДвижения(данные);\n" +
    "    if (движение) очкиЯчейка.appendChild(движение); /* порчено --сломать: дефис вернулся в карточку */"
  );
  const путь = path.join(os.tmpdir(), 'рейтинг-экран-сломать-дефис.js');
  fs.writeFileSync(путь, рабочийИсходник, 'utf8');
  рабочийИсходник = fs.readFileSync(путь, 'utf8');
  console.log('Ломающий запуск --сломать: копия в ' + путь);
  console.log('  карточка «Моё место» снова кладёт «—» при «безИзменений»/«нетДанных».');
  console.log('');
}

let провалов = 0;
let всегоПроверок = 0;

function проверить(имя, годно) {
  всегоПроверок += 1;
  console.log((годно ? '  ok  ' : ' ПЛОХО ') + имя);
  if (!годно) провалов += 1;
}

function ждать(мс) { return new Promise(function (r) { setTimeout(r, мс || 40); }); }

function fetchОтвет(данные) {
  return function () {
    return Promise.resolve({ json: function () { return Promise.resolve(данные); } });
  };
}

/** Строка списка/своя строка: те же поля, что присылает сервер. */
function рядИгрока(место, имя, очки, этоЯ, движение, сдвиг) {
  const запись = { место: место, имя: имя, очки: очки, побед: место, партий: место + 5, этоЯ: !!этоЯ };
  if (движение !== undefined) запись.движение = движение;
  if (сдвиг !== undefined) запись.сдвиг = сдвиг;
  return запись;
}

function строкаПоМесту(таблица, место) {
  if (!таблица) return null;
  const строки = Array.prototype.slice.call(таблица.querySelectorAll('.рейтинг-строка'));
  for (let и = 0; и < строки.length; и++) {
    if (строки[и].getAttribute('data-место') === String(место)) return строки[и];
  }
  return null;
}

/** Поднять экран с заданным ответом сервера и вернуть карточку «Моё место». */
async function открытьИВзятьКарточку(ответ) {
  const поднятый = бр.поднять(рабочийИсходник, { имяФайла: 'js/рейтинг-экран.js', fetch: fetchОтвет(ответ) });
  поднятый.окно.ЭкранРейтинга.открыть('дурак');
  await ждать();
  const карточка = поднятый.документ.getElementById('рейтинг-моё-место');
  return { поднятый: поднятый, карточка: карточка };
}

async function прогон() {
  /* ==== Пункты 1 и 5: «безИзменений» — своё место (без узла) и строка
     таблицы (не я, с узлом «—», колонку выравнивать по-прежнему надо) ====
     Места 1–3 у сервера — подиум (первая тройка карточками, без стрелки
     движения вовсе, см. отдельную функцию подиума), поэтому проверочные
     строки нарочно берём с 4-го места — это уже настоящая строка таблицы,
     функция «строкаТаблицы». */
  const ответБезИзменений = {
    ок: true, узналиВас: true, всего: 20, яВТаблице: true,
    я: рядИгрока(5, 'ЯБезИзменений', 40, true, 'безИзменений'),
    верхушка: [
      рядИгрока(1, 'Первый', 100),
      рядИгрока(2, 'Второй', 90),
      рядИгрока(3, 'Третий', 80)
    ],
    вокругМеня: [
      рядИгрока(4, 'Четвёртый', 70, false, 'безИзменений'),
      рядИгрока(5, 'ЯБезИзменений', 40, true, 'безИзменений'),
      рядИгрока(6, 'Шестой', 30, false, 'выросло', 3),
      рядИгрока(7, 'Седьмой', 20, false, 'упало', 2)
    ]
  };
  const { поднятый: поднятыйА, карточка: карточкаА } = await открытьИВзятьКарточку(ответБезИзменений);
  проверить('«безИзменений»: в карточке «Моё место» узла .рейтинг-движение НЕТ',
    Boolean(карточкаА) && !карточкаА.querySelector('.рейтинг-движение'));

  const таблицаА = поднятыйА.документ.getElementById('рейтинг-таблица');
  const строкаБезИзмен = строкаПоМесту(таблицаА, 4);
  const узелБезИзмен = строкаБезИзмен ? строкаБезИзмен.querySelector('.рейтинг-движение') : null;
  проверить('строка таблицы (место 4, безИзменений, не я): узел найден, класс «--нет», текст «—»',
    Boolean(узелБезИзмен) && узелБезИзмен.classList.contains('рейтинг-движение--нет') &&
    узелБезИзмен.textContent === '—');

  const строкаВыросло = строкаПоМесту(таблицаА, 6);
  const узелВыросло = строкаВыросло ? строкаВыросло.querySelector('.рейтинг-движение') : null;
  проверить('строка таблицы (место 6, выросло 3): узел найден, текст «↑ 3»',
    Boolean(узелВыросло) && узелВыросло.textContent === '↑ 3');

  const строкаУпало = строкаПоМесту(таблицаА, 7);
  const узелУпало = строкаУпало ? строкаУпало.querySelector('.рейтинг-движение') : null;
  проверить('строка таблицы (место 7, упало 2): узел найден, текст «↓ 2»',
    Boolean(узелУпало) && узелУпало.textContent === '↓ 2');
  проверить('ошибок в консоли нет (безИзменений)', поднятыйА.ошибкиКонсоли.length === 0);

  /* ==== Пункт 2: «нетДанных» — своё место, узла тоже нет ==== */
  const ответНетДанных = {
    ок: true, узналиВас: true, всего: 20, яВТаблице: true,
    я: рядИгрока(9, 'ЯНетДанных', 15, true, 'нетДанных'),
    верхушка: [рядИгрока(1, 'Первый', 100), рядИгрока(2, 'Второй', 90)],
    вокругМеня: [рядИгрока(9, 'ЯНетДанных', 15, true, 'нетДанных')]
  };
  const { поднятый: поднятыйБ, карточка: карточкаБ } = await открытьИВзятьКарточку(ответНетДанных);
  проверить('«нетДанных»: в карточке «Моё место» узла .рейтинг-движение НЕТ',
    Boolean(карточкаБ) && !карточкаБ.querySelector('.рейтинг-движение'));
  проверить('ошибок в консоли нет (нетДанных)', поднятыйБ.ошибкиКонсоли.length === 0);

  /* ==== Пункт 3: «выросло» на 3 — стрелка в карточке остаётся ==== */
  const ответВыросло = {
    ок: true, узналиВас: true, всего: 20, яВТаблице: true,
    я: рядИгрока(6, 'ЯВыросло', 33, true, 'выросло', 3),
    верхушка: [рядИгрока(1, 'Первый', 100)],
    вокругМеня: [рядИгрока(6, 'ЯВыросло', 33, true, 'выросло', 3)]
  };
  const { поднятый: поднятыйВ, карточка: карточкаВ } = await открытьИВзятьКарточку(ответВыросло);
  const узелВКарточкеВ = карточкаВ ? карточкаВ.querySelector('.рейтинг-движение') : null;
  проверить('«выросло» на 3: в карточке «Моё место» узел найден, текст «↑ 3»',
    Boolean(узелВКарточкеВ) && узелВКарточкеВ.textContent === '↑ 3');
  проверить('ошибок в консоли нет (выросло)', поднятыйВ.ошибкиКонсоли.length === 0);

  /* ==== Пункт 4: «упало» на 2 — стрелка в карточке остаётся ==== */
  const ответУпало = {
    ок: true, узналиВас: true, всего: 20, яВТаблице: true,
    я: рядИгрока(7, 'ЯУпало', 20, true, 'упало', 2),
    верхушка: [рядИгрока(1, 'Первый', 100)],
    вокругМеня: [рядИгрока(7, 'ЯУпало', 20, true, 'упало', 2)]
  };
  const { поднятый: поднятыйГ, карточка: карточкаГ } = await открытьИВзятьКарточку(ответУпало);
  const узелВКарточкеГ = карточкаГ ? карточкаГ.querySelector('.рейтинг-движение') : null;
  проверить('«упало» на 2: в карточке «Моё место» узел найден, текст «↓ 2»',
    Boolean(узелВКарточкеГ) && узелВКарточкеГ.textContent === '↓ 2');
  проверить('ошибок в консоли нет (упало)', поднятыйГ.ошибкиКонсоли.length === 0);

  console.log('');
  console.log('Итого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
  if (провалов) process.exit(1);
}

прогон().catch(function (ошибка) {
  console.error('Ошибка прогона:', ошибка);
  process.exit(1);
});
