/* =====================================================================
   СОСТАВ ВИТРИНЫ: карточные игры и временно спрятанные — трещотка.

   Просьба владельца (29.09.2026): паук, косынка и свободная ячейка —
   в категории «Карточные»; змейка, блоки 8×8, поиск слов и пятнашки
   пока спрятаны с витрины совсем, вечером того же дня — и три в ряд
   (их не должно быть ни в «Все игры»,
   ни в фильтрах — плитки просто убраны из разметки). Страницы этих
   четырёх игр и их js не трогаем — вернутся позже отдельной задачей.

   Что проверяем в index.html:
     1) у плиток паук / косынка / свободная-ячейка есть data-вид="карточные";
     2) плиток змейка / блоки / поиск-слов / пятнашки / три-в-ряд на витрине нет
        вовсе — ни одного тега с data-игра="<ключ>" (ноль найденного
        для «должна быть плитка» — это провал, а не тихий пропуск);
     3) головоломки в самом низу (просьба владельца 29.09): ни одна плитка
        data-вид="головоломки" не стоит в разметке выше какой-либо плитки
        другого вида — порядок читаем из самой разметки, второй копии
        списка плиток здесь нет.

   Запуск:
       node tests/витрина-состав.js                          — проект
       node tests/витрина-состав.js --сломать <путь-к-копии>  — ломающий запуск:
         путь ведёт на СВОЮ испорченную копию index.html во временной
         папке (os.tmpdir()) — готовит её тот, кто запускает проверку;
         настоящий файл проекта не трогаем. На испорченной копии
         проверка обязана найти провалы (покраснеть).
   ===================================================================== */

const fs = require('fs');
const path = require('path');

const ПРОЕКТ = path.join(__dirname, '..');

/* Игры, которым положено быть в «Карточных». */
const ДОЛЖНЫ_БЫТЬ_КАРТОЧНЫМИ = ['паук', 'косынка', 'свободная-ячейка'];

/* Игры, временно спрятанные с витрины (страницы и js не трогаем). */
const ДОЛЖНЫ_ИСЧЕЗНУТЬ = ['змейка', 'блоки', 'поиск-слов', 'пятнашки', 'три-в-ряд'];

function безКомментариев(текст) {
  return текст.replace(/<!--[\s\S]*?-->/g, '');
}

/* Все плитки data-игра="…" в тексте: ключ → список значений data-вид
   (обычно один, но считаем все — вдруг плитку задвоили по ошибке). */
function плиткиИзВитрины(html) {
  const плитки = {};
  безКомментариев(html).replace(/<(a|button)\s[^>]*data-игра="([^"]+)"[^>]*>/g, function (тег, имяТега, ключ) {
    const вид = /data-вид="([^"]+)"/.exec(тег);
    if (!плитки[ключ]) плитки[ключ] = [];
    плитки[ключ].push(вид ? вид[1] : null);
    return тег;
  });
  return плитки;
}

/* Плитки строго по порядку появления в разметке: [{ключ, вид}]. Не объект —
   у объекта JS ключи вида «2048» (похожие на число) сами уезжают в начало
   перебора, и порядок разметки для такой плитки терялся бы молча. */
function списокПлитокПоПорядку(html) {
  const список = [];
  const текст = безКомментариев(html);
  const образец = /<(a|button)\s[^>]*data-игра="([^"]+)"[^>]*>/g;
  let тег;
  while ((тег = образец.exec(текст))) {
    const вид = /data-вид="([^"]+)"/.exec(тег[0]);
    список.push({ ключ: тег[2], вид: вид ? вид[1] : null });
  }
  return список;
}

/** Проверить один файл витрины. Возвращает { проверок, провалы }. */
function проверитьФайл(путь, тихо) {
  const итог = { проверок: 0, провалы: [] };
  function сказать(т) { if (!тихо) console.log(т); }
  function проверить(условие, текстПровала, текстУспеха) {
    итог.проверок++;
    if (!условие) { итог.провалы.push(текстПровала); сказать('  ПРОВАЛ: ' + текстПровала); }
    else сказать('  ок: ' + текстУспеха);
  }

  сказать('Файл: ' + путь);
  if (!fs.existsSync(путь)) {
    проверить(false, 'файла нет: ' + путь, '');
    return итог;
  }
  const плитки = плиткиИзВитрины(fs.readFileSync(путь, 'utf8'));

  ДОЛЖНЫ_БЫТЬ_КАРТОЧНЫМИ.forEach(function (ключ) {
    const найдено = плитки[ключ] || [];
    проверить(найдено.length > 0,
      'плитки «' + ключ + '» нет на витрине совсем',
      'плитка «' + ключ + '» есть на витрине');
    if (найдено.length > 0) {
      проверить(найдено.every(function (в) { return в === 'карточные'; }),
        'плитка «' + ключ + '» не в «Карточных» (data-вид: ' + найдено.join(', ') + ')',
        'плитка «' + ключ + '» в «Карточных»');
    }
  });

  ДОЛЖНЫ_ИСЧЕЗНУТЬ.forEach(function (ключ) {
    const найдено = плитки[ключ] || [];
    проверить(найдено.length === 0,
      'плитка «' + ключ + '» всё ещё видна на витрине (должна быть спрятана)',
      'плитки «' + ключ + '» на витрине нет — спрятана');
  });

  /* Головоломки — в самом низу (просьба владельца 29.09): последняя
     не-головоломка обязана стоять раньше первой головоломки. Порядок
     берём из самой разметки (списокПлитокПоПорядку), не пересчитываем. */
  const список = списокПлитокПоПорядку(fs.readFileSync(путь, 'utf8'));
  const перваяГоловоломка = список.findIndex(function (з) { return з.вид === 'головоломки'; });
  const последняяНеГоловоломка = список.reduce(function (найдена, з, и) {
    return з.вид !== 'головоломки' ? и : найдена;
  }, -1);
  проверить(перваяГоловоломка === -1 || последняяНеГоловоломка < перваяГоловоломка,
    'плитка «головоломки» стоит выше не-головоломки (порядок: ' + список.map(function (з) { return з.ключ + '=' + з.вид; }).join(', ') + ')',
    'все головоломки стоят ниже настольных и карточных плиток');

  return итог;
}

/* ---------------- Запуск ---------------- */

const индексСломать = process.argv.indexOf('--сломать');
if (индексСломать !== -1) {
  const путь = process.argv[индексСломать + 1];
  if (!путь) {
    console.error('--сломать требует путь к испорченной копии index.html ' +
      '(готовит её тот, кто запускает проверку, во временной папке — настоящий файл не трогаем)');
    process.exit(1);
  }
  console.log('Ломающий запуск --сломать: копия обязана дать провалы.\n');
  const итог = проверитьФайл(путь, false);
  console.log('\nИтого проверок: ' + итог.проверок + ', провалов: ' + итог.провалы.length);
  if (!итог.провалы.length) {
    console.log('СЛЕПА: испорченная копия не дала ни одного провала — проверка не работает.');
    process.exit(1);
  }
  console.log('Провалы найдены — проверка распознала порчу, как и должна.');
  process.exit(0);
} else {
  const итог = проверитьФайл(path.join(ПРОЕКТ, 'index.html'), false);
  console.log('\nИтого проверок: ' + итог.проверок + ', провалов: ' + итог.провалы.length);
  process.exit(итог.провалы.length ? 1 : 0);
}
