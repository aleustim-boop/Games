/** Приказ из области «из» в первую её соседнюю: касание, касание, «Отдать приказ». */
function отдатьПриказ(м, из) {
  const партия = м.сохранение().партия;
  const соседи = м.окно.ЗахватКарты.соседство(м.Правила.картаПартии(партия))[из];
  const куда = (соседи || [])[0];
  if (!куда) return false;
  м.коснуться(м.центрОбласти(партия, из));
  м.коснуться(м.центрОбласти(партия, куда));
  if (!м.видна('захват-приказ')) return false;
  м.нажать('захват-приказ-отдать');
  return true;
}

