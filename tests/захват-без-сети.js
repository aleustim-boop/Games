function сломатьИПроверить(папка) {
  fs.mkdirSync(папка, { recursive: true });
  let худшийКод = 0;
  ПОРЧИ.forEach((порча, номер) => {
    const вВиде = порча.файл === 'вид';
    let испорчено = (вВиде ? fs.readFileSync(path.join(КОРЕНЬ, 'js', 'захват-карта-вид.js'), 'utf8') : исходникЭкрана).replace(/\r\n/g, '\n');
    const нетМеста = порча.замены.filter(([было]) => испорчено.indexOf(было) === -1);
    if (нетМеста.length) {
      console.log('Порча ' + (номер + 1) + ' («' + порча.имя + '»): в копии нет места для порчи — код 3');
      худшийКод = Math.max(худшийКод, 3);
      return;
    }
    порча.замены.forEach(([было, стало]) => { испорчено = испорчено.replace(было, стало); });
    const копия = path.join(папка, 'порча-без-сети-' + (номер + 1) + (вВиде ? '-вид' : '') + '.js');
    fs.writeFileSync(копия, испорчено, 'utf8');
    const запуск = spawnSync(process.execPath, [__filename, вВиде ? '--файл-вида' : '--файл', копия], { encoding: 'utf8' });
    const красных = (запуск.stdout.match(/^ПРОВАЛ: .*/gm) || []);
    console.log('Порча ' + (номер + 1) + ' («' + порча.имя + '»): код выхода ' + запуск.status + ', красных пунктов ' + красных.length);
    красных.forEach(с => console.log('   ' + с));
    if (запуск.status !== 1 || !красных.length) худшийКод = Math.max(худшийКод, 2);
  });
  console.log(худшийКод === 0 ? 'Все порчи проверка поймала.' : 'Ломающий запуск не удался, код ' + худшийКод);
  process.exit(худшийКод);
}

