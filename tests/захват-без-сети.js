  const черновик = м.сохранение().черновик;
  проверка('черновик: записана последняя правка (+3 в своей области)', !!черновик && черновик.расстановка[область] === 3, JSON.stringify(черновик));

  // Перезагрузка посреди приказов: черновик возвращается на стол.
  const б = мир({ ящик: м.ящик(), посев: 6 });
  б.нажать('захват-продолжить');
  проверка('черновик: после перезагрузки раунд тот же, разборов нет', б.строкаРаунда() === 'Раунд 1 из 10' && б.разборов === 0);
  // Что стол держит, видно по тому, с чем он уходит в «Готово»: в новом мире и в старом должно уйти одно и то же.
  м.готово();
  б.готово();
  const изСтарого = м.черновикиЧеловека[0];
  const изНового = б.черновикиЧеловека[0];
  проверка('черновик: «Готово» в старом мире ушло с правкой (+3 в своей области)', !!изСтарого && изСтарого.расстановка[область] === 3, JSON.stringify(изСтарого));
