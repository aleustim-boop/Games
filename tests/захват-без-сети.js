/* ---------- 11. победители: 4 места, человек 1-й, 2-й и 3-й (ответ владельца 01.10) ---------- */

/** Законченная по раундам партия, где человек на нужном месте: области раздаются 8, 6, 4, 2 по порядку мест. */
function партияСМестом(м, место) {
  const п = JSON.parse(JSON.stringify(м.сохранение().партия));
  const столицы = new Set(п.столицы.map(с => с.область));
  const простые = [];
  for (let н = 1; н < п.хозяева.length; н++) if (!столицы.has(н)) { простые.push(н); п.хозяева[н] = null; }
  const порядок = п.игроки.filter(к => к !== 'человек');
  порядок.splice(место - 1, 0, 'человек');
  const сколько = [8, 6, 4, 2];
  let взято = 0;
  порядок.forEach((к, н) => { for (let i = 0; i < сколько[н]; i++) п.хозяева[простые[взято++]] = к; });
  if (взято > простые.length) return null;
  // Поля конца — так же, как их пишут правила в миг конца (договор 15.2).
  п.раунд = п.всегоРаундов;
  п.завершена = true;
  п.конец = { причина: 'раунды', победитель: null, раунд: п.раунд };
  return Object.assign(п, м.Правила.итог(п));
}

