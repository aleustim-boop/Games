  const задержка = м.Правила.ЧИСЛА.задержкаЧерновикаМс;
  м.таймеры.прошло(задержка - 1);
  проверка('черновик: за 399 мс после последней правки записи нет', м.записиСохранения === записейДо, 'записей ' + (м.записиСохранения - записейДо));
