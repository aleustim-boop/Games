/** Часы раскрытия: сколько мс прошло с «Готово»; кадры — через ручной requestAnimationFrame. */
function часыРаскрытия(м) {
  let прошло = 0;
  const ч = {
    сейчас: () => прошло,
    до(мс) { if (мс > прошло) { м.таймеры.прошло(мс - прошло); прошло = мс; } },
    плюс(мс) { м.таймеры.прошло(мс); прошло += мс; },
    /** Каждые шаг мс: время вперёд, кадр на холст, дело(). */
    кадрами(мс, шаг, дело) { for (let т = 0; т < мс; т += шаг) { ч.плюс(шаг); м.кадры.выпустить(); if (дело) дело(); } }
  };
  return ч;
}

