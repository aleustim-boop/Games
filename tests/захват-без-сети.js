/* ---------- поддельные таймеры и случай ---------- */

/** Таймеры на поддельных часах: прошло(мс) по порядку зовёт всё, чей срок настал. */
function сделатьТаймеры(часы) {
  let последний = 0;
  const очередь = [];
  const т = {
    setTimeout: (дело, мс) => {
      последний++;
      очередь.push({ номер: последний, когда: часы.сейчас() + Math.max(0, Number(мс) || 0), дело });
      return последний;
    },
    clearTimeout: номер => {
      const где = очередь.findIndex(з => з.номер === номер);
      if (где !== -1) очередь.splice(где, 1);
    },
    прошло: мс => {
      const до = часы.сейчас() + мс;
      for (;;) {
        let лучший = -1;
        очередь.forEach((з, и) => {
          if (з.когда > до) return;
          if (лучший === -1 || з.когда < очередь[лучший].когда || (з.когда === очередь[лучший].когда && з.номер < очередь[лучший].номер)) лучший = и;
        });
        if (лучший === -1) break;
        const з = очередь.splice(лучший, 1)[0];
        часы.установить(з.когда);
        з.дело();
      }
      часы.установить(до);
    },
    ждут: () => очередь.length
  };
  return т;
}

/** Случай с посевом: один посев — одна и та же партия. */
function случайСПосевом(посев) {
  let с = посев >>> 0;
  return () => { с = (Math.imul(с, 1664525) + 1013904223) >>> 0; return с / 4294967296; };
}

