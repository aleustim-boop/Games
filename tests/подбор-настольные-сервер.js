/* =====================================================================
   ПОДБОР ДЕБЕРЦА, ДОМИНО И МОНОПОЛИИ НА СЕРВЕРЕ (план-подбор-четыре-игры.md,
   этап Э1)

   Что проверяем. Дверь /подбор (та же, что у шашек и нард — см.
   tests/подбор-шашки-нарды-сервер.js) теперь понимает ещё три слова поля
   «игра»: деберц, домино, монополия. Столы этих игр стартуют сами уже
   на двоих (мин игроков — 2 у всех трёх), поэтому местВСтоле не меняли.
   Проверяем по пунктам — у каждого своя буква, по ней ломающий запуск
   ищет провал:
     А — двое «деберц» сведены за один стол деберца, партия идёт сама;
     Б — то же для домино;
     В — то же для монополии;
     Г — одиночка в каждой из трёх, не дождавшись соперника, получает
         бота уровня «обычный» за столом своей игры;
     Ж — очереди раздельные: деберц не встречается с домино;
     И — катан по-прежнему отказан словами (он не в белом списке Э1,
         его подбор ждёт Э2 — добор ботами).

   Какой server/ проверять — довод «--корень <папка>» (папка, внутри
   которой лежат server/ и js/). Без довода — папка проекта.

   Свой сервер поднимается в этом же процессе на порту 8819 (боевой 8790
   и порт шашек-нард 8818 не трогаем), Telegram поддельный, данные уведены
   во временную папку.

   Запуск:
       node tests/подбор-настольные-сервер.js
       node tests/подбор-настольные-сервер.js --корень <папка-с-копией>

   Ломающий прогон словом:
       node tests/подбор-настольные-сервер.js --сломать=А
   (буквы А, Б, В, Г, Ж, И — какое ожидание подменить одним словом).
   Плюс настоящая порча всей копии server/ и js/ — --корень на папку, где
   деберц вычеркнут из ИГРЫ_ПОДБОРА: буква А (и Ж заодно) обязана
   покраснеть.

   Выход 0 — провалов нет, 1 — есть.
   ===================================================================== */

const path = require('path');
const os = require('os');
const http = require('http');
const crypto = require('crypto');

const ПРОЕКТ = path.join(__dirname, '..');
const ПОРТ = 8819;
const ХОЗЯИН_АДРЕС = '127.0.0.1';

/* Выдуманный токен: с настоящим токеном бота ничего общего. */
const ТОКЕН_ДЛЯ_ПРОБЫ = '1234567:VYDUMANNYY-TOKEN-DLYA-PROVERKI-podbora-nastolnyh';

function доводПосле(имя) {
  const где = process.argv.indexOf(имя);
  return где !== -1 ? process.argv[где + 1] : null;
}

function доводРавно(имя) {
  const строка = process.argv.find(function (а) { return а.indexOf(имя + '=') === 0; });
  return строка ? строка.slice(имя.length + 1) : null;
}

let проверок = 0;
const провалы = [];

/** Буква — пункт из шапки; по ней ломающий запуск понимает, что покраснело. */
function проверить(буква, условие, что) {
  проверок++;
  if (!условие) {
    провалы.push('[' + буква + '] ' + что);
    console.log('  ПРОВАЛ [' + буква + '] ' + что);
  }
}

/* =====================================================================
   ЛОМАЮЩИЙ ЗАПУСК «--сломать=буква»: подменяет одно ожидание проверки же
   самой (не файл проекта), проверка обязана покраснеть ровно этой буквой.
   ===================================================================== */
const СЛОМАТЬ = доводРавно('--сломать');

function подписать(поля, токен) {
  const строки = Object.keys(поля)
    .filter(function (к) { return к !== 'hash'; })
    .map(function (к) { return к + '=' + поля[к]; })
    .sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(токен).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}

/** initData так, как её присылает настоящая страница Telegram. */
function подписьИгрока(номер, имя) {
  const поля = {
    query_id: 'AAF' + номер,
    user: JSON.stringify({ id: номер, first_name: имя, username: 'igrok' + номер }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  const сподписью = Object.assign({}, поля, { hash: подписать(поля, ТОКЕН_ДЛЯ_ПРОБЫ) });
  return Object.keys(сподписью)
    .map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(сподписью[к]); })
    .join('&');
}

function спросить(путь, тело) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН_АДРЕС, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (сбой) { разобрано = null; }
        готово({ код: ответ.statusCode, тело: разобрано || {} });
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

/** Встать в очередь от имени игрока; лишние поля тела — как есть. */
function встать(номер, имя, поля) {
  return спросить('/подбор', Object.assign({ initData: подписьИгрока(номер, имя) }, поля));
}

function новости(ключ) {
  return спросить('/подбор-новости', { ключОжидания: ключ });
}

function отменить(ключ) {
  return спросить('/подбор-отмена', { ключОжидания: ключ });
}

async function проверитьВсё(комнаты, подбор) {

  /** Комната по коду и пропуску — прямо из модуля, тем же кэшем require, что у сервера. */
  function комнатаПо(код, пропуск) {
    const найдено = код && пропуск ? комнаты.найтиИгрока(код, пропуск) : null;
    return найдено ? найдено.комната : null;
  }

  async function этапГлазами(код, пропуск) {
    const ответ = await спросить('/состояние', { код: код, пропуск: пропуск });
    return ответ.тело && ответ.тело.состояние ? ответ.тело.состояние.этап : null;
  }

  /** Пара одной игры: первый ждёт, второй сразу сведён, первый узнаёт опросом. */
  async function сверитьПару(буква, игра, первый, второй) {
    /* --сломать=А/Б/В: второй тоже встаёт под чужой игрой — своя пара не сойдётся. */
    const играВторого = (СЛОМАТЬ === буква) ? 'дурак' : игра;
    const о1 = await встать(первый[0], первый[1], { игра: игра });
    проверить(буква, о1.тело.статус === 'ждёт' && typeof о1.тело.ключОжидания === 'string',
      игра + ': первый встаёт в очередь и ждёт');
    const о2 = await встать(второй[0], второй[1], { игра: играВторого });
    проверить(буква, о2.тело.статус === 'свели' && Boolean(о2.тело.код),
      игра + ': второй сразу сведён с первым');
    const н1 = о1.тело.ключОжидания ? await новости(о1.тело.ключОжидания) : { тело: {} };
    проверить(буква, н1.тело.статус === 'свели' && н1.тело.код === о2.тело.код,
      игра + ': первый узнаёт о сведении, код стола у обоих один');
    const комната = комнатаПо(о2.тело.код, о2.тело.пропуск);
    проверить(буква, Boolean(комната) && комната.игра === игра,
      игра + ': стол заведён именно под эту игру (за столом: ' + (комната && комната.игра) + ')');
    проверить(буква, (await этапГлазами(н1.тело.код, н1.тело.пропуск)) === 'игра',
      игра + ': партия началась сама, без кнопки «Начать»');
    if (играВторого !== игра) {
      /* Пары не вышло (нарочная порча) — оба остались в разных очередях, прибираем. */
      if (о1.тело.ключОжидания) await отменить(о1.тело.ключОжидания);
      if (о2.тело.ключОжидания) await отменить(о2.тело.ключОжидания);
    }
  }

  console.log('А. Двое «деберц» сведены за стол деберца');
  await сверитьПару('А', 'деберц', [601, 'Аня'], [602, 'Боря']);

  console.log('Б. Двое «домино» сведены за стол домино');
  await сверитьПару('Б', 'домино', [603, 'Вера'], [604, 'Гоша']);

  console.log('В. Двое «монополия» сведены за стол монополии');
  await сверитьПару('В', 'монополия', [605, 'Даша'], [606, 'Егор']);

  console.log('Г. Одиночке в каждой из трёх подсаживают бота «обычный»');
  подбор.подменитьПорогОжиданияДляПроверки(300);
  try {
    for (const [игра, номер] of [['деберц', 610], ['домино', 611], ['монополия', 612]]) {
      const о = await встать(номер, 'Одиночка', { игра: игра });
      проверить('Г', о.тело.статус === 'ждёт', игра + ': одиночка ждёт');
      const н = о.тело.ключОжидания ? await новости(о.тело.ключОжидания) : { тело: {} };
      проверить('Г', н.тело.статус === 'свели' && Boolean(н.тело.код),
        игра + ': порог истёк — отдали код стола с ботом');
      const комната = комнатаПо(н.тело.код, н.тело.пропуск);
      const бот = комната ? Object.values(комната.игроки).find(function (и) { return и && и.этоБот; }) : null;
      проверить('Г', Boolean(комната) && комната.игра === игра,
        игра + ': стол с ботом той же игры (за столом: ' + (комната && комната.игра) + ')');
      /* --сломать=Г: ждём заведомо неверный уровень — бот сядет «обычным», проверка покраснеет. */
      const ждёмУровень = (СЛОМАТЬ === 'Г') ? 'мастер' : 'обычный';
      проверить('Г', Boolean(бот) && бот.уровень === ждёмУровень,
        игра + ': бот уровня «' + ждёмУровень + '» (сел: ' + (бот && бот.уровень) + ')');
      проверить('Г', (await этапГлазами(н.тело.код, н.тело.пропуск)) === 'игра',
        игра + ': с ботом партия началась сама');
    }
  } finally {
    подбор.подменитьПорогОжиданияДляПроверки();
  }

  console.log('Ж. Очереди раздельные: деберц не встречается с домино');
  const деберц = await встать(620, 'Женя', { игра: 'деберц' });
  const домино = await встать(621, 'Зина', { игра: 'домино' });
  /* --сломать=Ж: считаем, что второй тоже должен был свестись с первым — покраснеет. */
  const ждёмДомино = (СЛОМАТЬ === 'Ж') ? 'свели' : 'ждёт';
  проверить('Ж', деберц.тело.статус === 'ждёт', 'деберц ждёт в своей очереди');
  проверить('Ж', домино.тело.статус === ждёмДомино,
    'домино после деберца не сведено с ним, ждёт своей очереди');
  for (const о of [деберц, домино]) {
    if (о.тело.ключОжидания) await отменить(о.тело.ключОжидания);
  }

  console.log('И. Катан по-прежнему отказан словами (его добор — Э2)');
  const катан = await встать(630, 'Иван', { игра: 'катан' });
  /* --сломать=И: как будто катан уже принят подбором — ждём «ждёт», хотя должен быть отказ. */
  const ждёмСтатусКатана = (СЛОМАТЬ === 'И') ? 'ждёт' : undefined;
  if (ждёмСтатусКатана) {
    проверить('И', катан.тело.статус === ждёмСтатусКатана,
      'катан: подделанное ожидание — подбор его якобы принял');
  } else {
    проверить('И', катан.тело.ок === false && typeof катан.тело.причина === 'string' &&
      катан.тело.причина.length > 10 && !катан.тело.ключОжидания,
      'катан: отказ словами без ключа ожидания');
  }
  if (катан.тело.ключОжидания) await отменить(катан.тело.ключОжидания);
}

async function проверять() {
  const корень = path.resolve(доводПосле('--корень') || ПРОЕКТ);

  /* Данные уводим ДО подключения сервера — боевые знакомства не трогаем. */
  process.env.ДАННЫЕ_ИГРЫ = path.join(os.tmpdir(), 'подбор-настольные-' + process.pid);

  const сервера = require(path.join(корень, 'server', 'сервер.js'));
  /* Те же модули, что require'ит сервер (один кэш require). */
  const подбор = require(path.join(корень, 'server', 'подбор.js'));
  const комнаты = require(path.join(корень, 'server', 'комнаты.js'));

  console.log('=== Подбор деберца, домино и монополии: очереди по играм, столы, бот ===');
  console.log('server/ из ' + корень);
  if (СЛОМАТЬ) console.log('ЛОМАЮЩИЙ ЗАПУСК: --сломать=' + СЛОМАТЬ);
  console.log('свой сервер на http://' + ХОЗЯИН_АДРЕС + ':' + ПОРТ + ' (боевой 8790 не трогаем)\n');

  сервера.оснасткаДляПроверки(ТОКЕН_ДЛЯ_ПРОБЫ, function () { return { ok: true }; });
  const сервер = сервера.создатьСервер();
  await new Promise(function (готово, беда) {
    сервер.once('error', беда);
    сервер.listen(ПОРТ, ХОЗЯИН_АДРЕС, готово);
  });

  let сбой = null;
  try {
    await проверитьВсё(комнаты, подбор);
  } catch (беда) {
    сбой = беда;
  }

  сервер.close();
  сервера.оснасткаДляПроверки();
  подбор.подменитьПорогОжиданияДляПроверки();

  console.log('\n----------------------------------------');
  if (сбой) {
    console.log('ПРОВЕРКА ОБОРВАЛАСЬ: ' + сбой.message);
    console.log(сбой.stack);
  }
  for (const беда of провалы) console.log('  - ' + беда);
  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалы.length);
  process.exit(сбой || провалы.length > 0 ? 1 : 0);
}

проверять();
