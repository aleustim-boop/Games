/* ---------- Перехват настоящего запроса POST /создать (js/сеть.js) ----------
   Не подменяем ни window.Сеть.создатьКомнату, ни window.ОнлайнЛобби.
   создатьСтол — реальный код должен дойти до защёлки «создаёмИгру» в
   js/сеть.js (создатьИгруНаСервере, ~3519), иначе тест не увидит, как
   она на самом деле работает. Каждый перехваченный POST /создать НЕ
   отвечаем сразу — кладём его «путь» (route) в очередь и ждём явного
   счёт.отпустить(тело): так проверка сама решает, когда сервер «ответит»
   и чем — успехом ({ код, пропуск }, экран уйдёт на комнату) или отказом
   ({ ошибка }, кнопка обязана вернуться в «Создать игру»). */
async function настроитьПерехватСоздания(страница) {
  const счёт = { раз: 0, задержанные: [] };
  await перехватить(страница, /\/создать(\?|$)/, (путь) => {
    счёт.раз++;
    счёт.задержанные.push(путь);
  });
  /** Ответить самому старому из задержанных запросов. false — очередь
      пуста (отвечать нечему — обычно значит, что шаг проверки перепутал
      порядок и запрос ещё не пришёл или уже разобран раньше). */
  счёт.отпустить = function (тело) {
    const путь = счёт.задержанные.shift();
    if (!путь) return false;
    путь.fulfill({
      status: 200,
      contentType: 'application/json; charset=utf-8',
      body: JSON.stringify(тело)
    });
    return true;
  };
  return счёт;
}

/** Прочитать текст и disabled кнопки «Создать игру» одним вызовом. */
async function состояниеКнопкиСоздать(страница) {
  return страница.evaluate(() => {
    const кнопка = document.getElementById('открытые-столы-создать');
    return кнопка ? { выключена: кнопка.disabled, текст: кнопка.textContent.trim() } : null;
  });
}

/* ---------- «Создать игру» у шашек и нард — настоящий путь дурака ----------
   С 30.09 (правка разработчика) кнопка «Создаём…» держится, ПОКА не
   пришёл ответ сервера — раньше сбрасывалась синхронно, теперь мастер
   отдаёт промис, и открытые-столы.js возвращает кнопку только в его
   .then. Проверяем четыре вещи на одной странице (счётчик запросов общий,
   поэтому между шагами обнуляем «раз» и явно разбираем очередь задержанных
   ответов):
   1) одно нажатие — ровно один запрос /создать; пока ответ задержан,
      кнопка выключена и подписана «Создаём…»; после ОТКАЗА сервера
      возвращается в «Создать игру» и включена;
   2) защёлка js/сеть.js, а не disabled кнопки: после первого клика кнопка
      сама выключена, и второй клик по ней браузер вообще не доставил бы —
      это проверяло бы кнопку, а не защёлку. Поэтому второй вызов идёт
      МИМО кнопки — напрямую вызываем мастера (window.НастройкиЭкранаОнлайн.
      создатьИгру()) через page.evaluate дважды подряд, пока первый ответ
      ещё задержан: до сервера обязан дойти ровно один POST /создать;
   3) «Создать игру» → сразу «Назад», не дожидаясь ответа (запрос остаётся
      задержанным нарочно) → снова открыли экран — кнопка рабочая, старый,
      так и не пришедший ответ её не портит;
   4) последним шагом (он безвозвратный — страница после него уже не на
      экране списка, поэтому вынесен в самый конец) — УСПЕШНЫЙ ответ
      /создать переводит экран на комнату (#экран-комнаты). */
async function проверитьСозданиеСтола(страница, имя) {
  const счёт = await настроитьПерехватСоздания(страница);

  // 1) Одно нажатие → один запрос; кнопка ждёт; отказ возвращает кнопку.
  let нажатие = await страница.evaluate(() => {
    const кнопка = document.getElementById('открытые-столы-создать');
    if (!кнопка) return null;
    кнопка.click();
    return { выключена: кнопка.disabled, текст: кнопка.textContent.trim() };
  });
  await страница.waitForTimeout(250);
  проверить(нажатие !== null, имя + ': кнопка «Создать игру» нашлась');
  проверить(счёт.раз === 1, имя + ': одно нажатие «Создать игру» отправило ровно один запрос /создать (вышло ' + счёт.раз + ')');
  const покаВисит = await состояниеКнопкиСоздать(страница);
  проверить(Boolean(покаВисит) && покаВисит.выключена && покаВисит.текст === 'Создаём…',
    имя + ': пока ответ /создать задержан, кнопка выключена и подписана «Создаём…» (вышло ' + JSON.stringify(покаВисит) + ')');

  проверить(счёт.отпустить({ ошибка: 'проверка (тестовый сервер отказал нарочно)' }),
    имя + ': тестовый сервер ответил на задержанный запрос (отказом)');
  await страница.waitForTimeout(300);
  const послеОтказа = await состояниеКнопкиСоздать(страница);
  проверить(Boolean(послеОтказа) && !послеОтказа.выключена && послеОтказа.текст === 'Создать игру',
    имя + ': после отказа сервера кнопка вернулась в «Создать игру» и включена (вышло ' + JSON.stringify(послеОтказа) + ')');

  // 2) Защёлка js/сеть.js: два вызова мастера МИМО кнопки, пока первый
  //    ответ ещё задержан, обязаны дойти до сервера ОДНИМ запросом.
  счёт.раз = 0;
  const мастерЕсть = await страница.evaluate(() =>
    Boolean(window.НастройкиЭкранаОнлайн && typeof window.НастройкиЭкранаОнлайн.создатьИгру === 'function'));
  проверить(мастерЕсть, имя + ': window.НастройкиЭкранаОнлайн.создатьИгру есть — мастера можно звать мимо кнопки');
  await страница.evaluate(() => {
    if (window.НастройкиЭкранаОнлайн) {
      window.НастройкиЭкранаОнлайн.создатьИгру();
      window.НастройкиЭкранаОнлайн.создатьИгру();   // второй вызов мимо кнопки — не клик, а прямой вызов мастера
    }
  });
  await страница.waitForTimeout(300);
  проверить(счёт.раз === 1, имя + ': два подряд вызова мастера «создатьИгру» мимо кнопки — защёлка js/сеть.js пропустила один POST /создать (вышло ' + счёт.раз + ')');
  // Разбираем очередь целиком: при сломанной защёлке там может остаться и второй запрос.
  while (счёт.отпустить({ ошибка: 'проверка (тестовый сервер отказал нарочно)' })) { /* пусто — просто освобождаем route */ }
  await страница.waitForTimeout(200);

  // 3) «Создать игру» → «Назад» до ответа → новое открытие — кнопка рабочая.
  счёт.раз = 0;
  await страница.evaluate(() => document.getElementById('открытые-столы-создать')?.click());
  await переоткрыть(страница, 'лобби-найти-игру');
  const послеПереоткрытия = await состояниеКнопкиСоздать(страница);
  проверить(Boolean(послеПереоткрытия) && !послеПереоткрытия.выключена && послеПереоткрытия.текст === 'Создать игру',
    имя + ': после «Назад» до ответа сервера и нового открытия кнопка рабочая и подписана «Создать игру» (вышло ' +
    JSON.stringify(послеПереоткрытия) + ')');
  // Старый запрос так и не пришёл — отвечаем ему, чтобы не оставлять route висящим навсегда.
  while (счёт.отпустить({ ошибка: 'проверка (тестовый сервер отказал нарочно)' })) { /* пусто */ }
  // Даём браузеру время долетевшим fulfill() снять защёлку «создаёмИгру» в
  // js/сеть.js, иначе следующий клик (п.4) сам попадает в ещё не снятую
  // защёлку и тихо отклоняется без единого запроса на сервер.
  await страница.waitForTimeout(300);

  // 3.5) Отказ без обращения к серверу (связь не загрузилась): если убрать
  //      window.Сеть.создатьКомнату, мастер ответит отказом БЕЗ POST /создать,
  //      и узел сообщения должен показать причину, кнопка вернуться в рабочий вид.
  // Шаг только для шашек и нард (не для дурака).
  if (имя !== 'Дурак') {
    счёт.раз = 0;
    await страница.evaluate(() => {
      if (window.Сеть) {
        window.__настоящаяСоздатьКомнату = window.Сеть.создатьКомнату;
        window.Сеть.создатьКомнату = undefined;
      }
    });
    await страница.evaluate(() => document.getElementById('открытые-столы-создать')?.click());
    // Ждём, пока сообщение об ошибке появится (мастер ответит отказом без обращения к серверу)
    try {
      await страница.waitForFunction(() => {
        const узел = document.getElementById('открытые-столы-сообщение');
        return узел && !узел.classList.contains('скрыт') && узел.textContent.includes('Связь');
      }, { timeout: 3000 });
    } catch (е) {
      /* сообщение не появилось — проверка покраснеет ниже */
    }
    await страница.waitForTimeout(300);
    проверить(счёт.раз === 0, имя + ': отказ без обращения к серверу — на сервер не ушло ни одного POST /создать (вышло ' + счёт.раз + ')');

    const сообщение = await страница.evaluate(() => {
      const узел = document.getElementById('открытые-столы-сообщение');
      return узел ? узел.textContent : '';
    });
    проверить(сообщение.includes('Связь с сервером не загрузилась'),
      имя + ': в узле сообщения появился текст о проблеме связи (вышло: «' + сообщение + '»)');

    // Возвращаем window.Сеть.создатьКомнату
    await страница.evaluate(() => {
      if (window.__настоящаяСоздатьКомнату !== undefined) {
        window.Сеть.создатьКомнату = window.__настоящаяСоздатьКомнату;
        delete window.__настоящаяСоздатьКомнату;
      }
    });
    const восстановлено = await страница.evaluate(() => typeof window.Сеть?.создатьКомнату === 'function');
    проверить(восстановлено, имя + ': window.Сеть.создатьКомнату восстановлено');
  }

  // 4) Последний шаг — УСПЕХ: экран уходит на комнату. Дальше страница для
  //    шагов списка уже не годится, поэтому это самый конец функции.
  счёт.раз = 0;
  await страница.evaluate(() => document.getElementById('открытые-столы-создать')?.click());
  await страница.waitForTimeout(250);
  проверить(счёт.раз === 1, имя + ': перед успешным ответом снова один запрос /создать (вышло ' + счёт.раз + ')');
  счёт.отпустить({ код: 'ПРОВЕРКА-' + имя.toUpperCase(), пропуск: 'секрет-проверки' });
  await страница.waitForTimeout(500);
  const наКомнате = await страница.evaluate(() =>
    Boolean(document.getElementById('экран-комнаты') && document.getElementById('экран-комнаты').classList.contains('экран--виден')));
  проверить(наКомнате, имя + ': успешный ответ /создать перевёл экран на комнату (#экран-комнаты)');
}

