/** Заменить кусок и убедиться, что замена правда случилась —
    иначе «поломка» ничего не поломала бы и прогон врал бы.
    Файлы на диске бывают в CRLF (\r\n), а образцы искомого текста в
    этом файле записаны с обычным \n — перед поиском переносы строк
    нормализуем (\r?\n → \n), иначе многострочный образец на CRLF-файле
    не найдётся никогда. Порченую копию отдаём как есть (уже с \n). */
function заменитьОбязательно(текст, было, стало, имя) {
  текст = текст.replace(/\r\n/g, '\n');
  if (текст.indexOf(было) === -1) throw new Error('Не нашёл, что портить в ' + имя + ': ' + было);
  return текст.replace(было, стало);
}

