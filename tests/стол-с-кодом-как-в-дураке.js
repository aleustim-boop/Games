/** Заменить кусок и убедиться, что замена правда случилась —
    иначе «поломка» ничего не поломала бы и прогон врал бы. */
function заменитьОбязательно(текст, было, стало, имя) {
  if (текст.indexOf(было) === -1) throw new Error('Не нашёл, что портить в ' + имя + ': ' + было);
  return текст.replace(было, стало);
}

function сделатьПорченыеКопии() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'стол-с-кодом-'));
  let столы = fs.readFileSync(path.join(КОРЕНЬ, 'js', 'открытые-столы.js'), 'utf8');
  // Возвращаем старое: на непустом списке кнопка «Создать» прячется.
  столы = заменитьОбязательно(столы,
    "    показатьСообщение('');\n    for (const стол of ответ.столы)",
    "    показатьСообщение('');\n    узел(КНОПКА_СОЗДАТЬ).classList.add('скрыт');\n    for (const стол of ответ.столы)",
    'js/открытые-столы.js');
  // Возвращаем старый заголовок «Найти игру» у шашек и нард.
  столы = заменитьОбязательно(столы,
    "заголовокЭкрана('Играть онлайн')",
    "заголовокЭкрана(дурак ? 'Играть онлайн' : 'Найти игру')",
    'js/открытые-столы.js');
  // Убираем сброс кнопки при открытии экрана: после «Назад» во время
  // «Создаём…» кнопка снова навсегда выключена.
  столы = заменитьОбязательно(столы,
    "    кнопка.disabled = false;\n    кнопка.textContent = 'Создать игру';\n  }",
    '  }',
    'js/открытые-столы.js');
  let шашки = fs.readFileSync(path.join(КОРЕНЬ, 'шашки.html'), 'utf8');
  // Возвращаем строку «Есть код?» в лобби шашек.
  шашки = заменитьОбязательно(шашки,
    '<nav class="нижние-вкладки" data-вкладки="лобби-шашек"',
    '<button id="лобби-код" type="button" class="лобби__код">Есть код? Войти</button>\n    <nav class="нижние-вкладки" data-вкладки="лобби-шашек"',
    'шашки.html');
  let стили = fs.readFileSync(path.join(КОРЕНЬ, 'style.css'), 'utf8');
  // --сломать: стрелкой «‹» «Назад» снова становится только у дурака.
  // --сломать-подложку: стрелка есть, но без веса «#приложение» —
  // у шашек и нард её перекрашивает в салатовую плашку их файл оформления.
  стили = заменитьОбязательно(стили,
    '#кнопка-рейтинг-игроков-назад,\n#приложение #открытые-столы-назад {',
    СЛОМАТЬ_ПОДЛОЖКУ ? '#кнопка-рейтинг-игроков-назад,\n#открытые-столы-назад {' : '#кнопка-рейтинг-игроков-назад {',
    'style.css');
  const путьСтолы = path.join(папка, 'открытые-столы.js');
  const путьШашки = path.join(папка, 'шашки.html');
  const путьСтили = path.join(папка, 'style.css');
  fs.writeFileSync(путьСтолы, столы);
  fs.writeFileSync(путьШашки, шашки);
  fs.writeFileSync(путьСтили, стили);
  console.log('Порченые копии: ' + папка);
  return { столы: путьСтолы, шашки: путьШашки, стили: путьСтили };
}

async function подсунутьКопии(страница, копии) {
  await перехватить(страница, /\/js\/открытые-столы\.js(\?|$)|\/шашки\.html(\?|$)|\/style\.css(\?|$)/, (путь, запрос, адрес) => {
    const файл = /открытые-столы\.js/.test(адрес) ? копии.столы
      : (/style\.css/.test(адрес) ? копии.стили : копии.шашки);
    if (файл.endsWith('.css')) {
      путь.fulfill({ status: 200, contentType: 'text/css; charset=utf-8', body: fs.readFileSync(файл, 'utf8') });
      return;
    }
    const тип = файл.endsWith('.js') ? 'application/javascript; charset=utf-8' : 'text/html; charset=utf-8';
    путь.fulfill({ status: 200, contentType: тип, body: fs.readFileSync(файл, 'utf8') });
  });
}

/* ---------- Что смотрим в странице ---------- */

/** Строка «Есть код?» в лобби: по id и по тексту (узел могли переименовать). */
async function кодВЛобби(страница) {
  return страница.evaluate(() => {
    const лобби = document.getElementById('экран-лобби');
    if (!лобби) return null;
    const поТексту = Array.from(лобби.querySelectorAll('button, a'))
      .filter((у) => /Есть код/.test(у.textContent || '')).map((у) => у.id || у.className);
    return { поId: Boolean(document.getElementById('лобби-код')), поТексту: поТексту };
  });
}

/** Состояние экрана онлайн: видим ли он, кнопки, их порядок. */
async function видЭкранаОнлайн(страница) {
  return страница.evaluate(() => {
    const экран = document.getElementById('экран-открытые-столы');
    if (!экран) return null;
    const видно = (у) => Boolean(у && !у.classList.contains('скрыт') && у.offsetParent !== null);
    const создать = document.getElementById('открытые-столы-создать');
    const код = document.getElementById('открытые-столы-код');
    const список = document.getElementById('открытые-столы-список');
    const порядок = Array.from(экран.children).map((у) => у.id).filter(Boolean);
    return {
      экранВиден: экран.classList.contains('экран--виден'),
      создатьЕсть: Boolean(создать && экран.contains(создать)),
      создатьВидна: видно(создать),
      создатьТекст: создать ? создать.textContent.trim() : '',
      кодЕсть: Boolean(код && экран.contains(код)),
      кодВиден: видно(код),
      кодТекст: код ? код.textContent.trim() : '',
      строкСтолов: список ? список.querySelectorAll('.таблица__строка').length : -1,
      порядок: порядок
    };
  });
}

/** Заголовок экрана онлайн; null — узла нет (это провал, не пропуск). */
async function заголовокОнлайн(страница) {
  return страница.evaluate(() => {
    const у = document.querySelector('#экран-открытые-столы .заголовок');
    return у ? у.textContent.trim() : null;
  });
}

/** Замер кнопки «Назад» экрана онлайн: где стоит и какого размера.
    null — узла нет (провал, не пропуск). */
async function замерНазад(страница) {
  return страница.evaluate(() => {
    const н = document.getElementById('открытые-столы-назад');
    const з = document.querySelector('#экран-открытые-столы .заголовок');
    if (!н || !з) return null;
    const р = н.getBoundingClientRect();
    const рз = з.getBoundingClientRect();
    const значок = getComputedStyle(н, '::before');
    const вид = getComputedStyle(н);
    return {
      фон: вид.backgroundColor + ' ' + вид.backgroundImage,
      цвет: вид.color,
      x: Math.round(р.left), y: Math.round(р.top), ш: Math.round(р.width), в: Math.round(р.height),
      надЗаголовком: р.bottom <= рз.top + 1,
      естьЗначок: значок.content !== 'none' && значок.content !== '' && значок.content !== 'normal',
      видна: р.width > 0 && р.height > 0
    };
  });
}

/** Замеры «Назад» по играм — сравниваем с дураком в конце прогона. */
const замерыНазад = {};

function проверитьНазадСтрелкой(замер, имя) {
  проверить(замер !== null, имя + ': кнопка «Назад» (#открытые-столы-назад) и заголовок нашлись');
  if (!замер) return;
  проверить(замер.видна, имя + ': стрелка «‹» видна');
  проверить(замер.ш <= 48 && замер.в <= 48,
    имя + ': «Назад» — маленькая стрелка, а не большая кнопка (' + замер.ш + '×' + замер.в + ')');
  проверить(замер.надЗаголовком, имя + ': стрелка стоит в шапке, над заголовком');
  проверить(замер.естьЗначок, имя + ': у стрелки есть значок «‹»');
}

function сравнитьСДураком() {
  console.log('\n=== Стрелка «‹»: положение и размер как у дурака ===');
  const эталон = замерыНазад['Дурак'];
  проверить(Boolean(эталон), 'замер стрелки у дурака есть');
  for (const имя of ['Шашки', 'Нарды']) {
    const з = замерыНазад[имя];
    проверить(Boolean(з), имя + ': замер стрелки есть');
    if (!з || !эталон) continue;
    const совпало = Math.abs(з.x - эталон.x) <= 2 && Math.abs(з.y - эталон.y) <= 2 &&
      з.ш === эталон.ш && з.в === эталон.в;
    проверить(совпало, имя + ': стрелка на том же месте и того же размера, что у дурака (' +
      [з.x, з.y, з.ш, з.в].join(',') + ' против ' + [эталон.x, эталон.y, эталон.ш, эталон.в].join(',') + ')');
    проверить(з.фон === эталон.фон && з.цвет === эталон.цвет,
      имя + ': стрелка того же цвета и без подложки, как у дурака (фон «' + з.фон + '», цвет ' + з.цвет +
      ' против «' + эталон.фон + '», ' + эталон.цвет + ')');
  }
}

/** Подменяем дверь списка: сколько столов вернёт сервер. */
async function подменитьСписок(страница, сколько) {
  await страница.evaluate((сколько) => {
    const столы = [];
    for (let i = 0; i < сколько; i++) {
      столы.push({ ключ: 'к' + i, занято: 1, мест: 2, игроки: ['Игрок ' + (i + 1)], ждётСекунд: 30 });
    }
    window.Сеть = window.Сеть || {};
    window.Сеть.открытыеСтолы = () => Promise.resolve({ ок: true, узналиВас: true, столы: столы });
  }, сколько);
}

async function открытьОнлайн(страница, idКарточки) {
  const нажато = await страница.evaluate((id) => {
    const к = document.getElementById(id);
    if (!к) return false;
    к.click();
    return true;
  }, idКарточки);
  await страница.waitForTimeout(500);
  return нажато;
}

/** Закрыть экран «Назад» и открыть заново — так список запросится свежим. */
async function переоткрыть(страница, idКарточки) {
  await страница.evaluate(() => document.getElementById('открытые-столы-назад')?.click());
  // Экран сам не спрашивает сервер чаще раза в ~1,1 с (РЕЖЕ_ЧЕМ_РАЗ_В).
  await страница.waitForTimeout(1300);
  return открытьОнлайн(страница, idКарточки);
}

function проверитьМесто(вид, имя) {
  const п = вид.порядок;
  const iСписок = п.indexOf('открытые-столы-список');
  const iСоздать = п.indexOf('открытые-столы-создать');
  const iКод = п.indexOf('открытые-столы-код');
  const iНазад = п.indexOf('открытые-столы-назад');
  проверить(iСписок >= 0 && iСоздать > iСписок && iКод > iСоздать && iНазад > iКод,
    имя + ': порядок как у дурака — список, «Создать игру», «Есть код?», «Назад» (вышло: ' + п.join(', ') + ')');
}

async function новаяСтраница(браузер, копии) {
  const контекст = await браузер.newContext({ viewport: { width: 390, height: 844 } });
  const страница = await контекст.newPage();
  const ошибки = [];
  страница.on('pageerror', (о) => ошибки.push('исключение: ' + о.message));
  страница.on('console', (с) => {
    if (с.type() === 'error' && !/Failed to load resource/.test(с.text())) ошибки.push('консоль: ' + с.text());
  });
  await безTelegram(страница);
  if (копии) await подсунутьКопии(страница, копии);
  return { контекст, страница, ошибки };
}

/* ---------- Шашки и нарды: полный путь ---------- */

async function проверитьИгру(браузер, копии, игра) {
  console.log('\n=== ' + игра.имя + ' ===');
  const { контекст, страница, ошибки } = await новаяСтраница(браузер, копии);
  await страница.goto(АДРЕС + игра.файл);
  await страница.waitForTimeout(600);

  const лобби = await кодВЛобби(страница);
  проверить(лобби !== null, игра.имя + ': #экран-лобби нашёлся');
  if (лобби) {
    проверить(!лобби.поId, игра.имя + ': в лобби нет узла #лобби-код');
    проверить(лобби.поТексту.length === 0, игра.имя + ': в лобби нет строки «Есть код?»' +
      (лобби.поТексту.length ? ' — а есть: ' + лобби.поТексту.join(', ') : ''));
  }

  // Пустой список.
  await подменитьСписок(страница, 0);
  проверить(await открытьОнлайн(страница, 'лобби-найти-игру'), игра.имя + ': карточка #лобби-найти-игру нашлась');
  let вид = await видЭкранаОнлайн(страница);
  проверить(вид !== null && вид.экранВиден, игра.имя + ': экран онлайн открылся');
  const заголовок = await заголовокОнлайн(страница);
  проверить(заголовок === 'Играть онлайн', игра.имя + ': заголовок «Играть онлайн», как у дурака (вышло «' +
    (заголовок === null ? 'узел не найден' : заголовок) + '»)');
  if (вид) {
    проверить(вид.строкСтолов === 0, игра.имя + ': список пуст (строк: ' + вид.строкСтолов + ')');
    проверить(вид.создатьЕсть && вид.создатьВидна, игра.имя + ': при ПУСТОМ списке «Создать игру» видна');
    проверить(вид.создатьТекст === 'Создать игру', игра.имя + ': подпись «Создать игру» (вышло «' + вид.создатьТекст + '»)');
    проверить(вид.кодЕсть && вид.кодВиден, игра.имя + ': «Есть код?» внутри экрана онлайн и видна');
    проверить(вид.кодТекст === 'Есть код? Войти', игра.имя + ': подпись «Есть код? Войти» (вышло «' + вид.кодТекст + '»)');
    проверитьМесто(вид, игра.имя);
  }

  // Непустой список.
  await подменитьСписок(страница, 2);
  await переоткрыть(страница, 'лобби-найти-игру');
  вид = await видЭкранаОнлайн(страница);
  проверить(вид !== null && вид.строкСтолов === 2, игра.имя + ': в списке два стола (строк: ' + (вид ? вид.строкСтолов : 'нет экрана') + ')');
  проверить(Boolean(вид && вид.создатьВидна), игра.имя + ': при НЕПУСТОМ списке «Создать игру» видна');
  замерыНазад[игра.имя] = await замерНазад(страница);
  проверитьНазадСтрелкой(замерыНазад[игра.имя], игра.имя);
  if (игра.снимок) {
    await страница.screenshot({ path: игра.снимок });
    console.log('  снимок: ' + игра.снимок);
  }

  // «Создать игру» — стол сразу, без шагов: зовёт Сеть.создатьОткрытыйСтол.
  const созданий = await страница.evaluate(() => {
    let раз = 0;
    window.Сеть.создатьОткрытыйСтол = () => { раз++; return Promise.resolve({ ок: false, причина: 'проверка' }); };
    document.getElementById('открытые-столы-создать')?.click();
    return раз;
  });
  проверить(созданий === 1, игра.имя + ': «Создать игру» позвала Сеть.создатьОткрытыйСтол один раз (вышло ' + созданий + ')');

  await проверитьПоздныйОтвет(страница, игра.имя);

  // «Есть код?» жмёт скрытую дверь js/сеть.js.
  const входов = await страница.evaluate(() => {
    const дверь = document.getElementById('кнопка-войти-по-коду');
    if (!дверь) return -1;
    let раз = 0;
    дверь.addEventListener('click', () => { раз++; });
    document.getElementById('открытые-столы-код')?.click();
    return раз;
  });
  проверить(входов === 1, игра.имя + ': «Есть код?» нажала «кнопка-войти-по-коду» (вышло ' + входов + ')');

  проверить(ошибки.length === 0, игра.имя + ': красных ошибок в консоли нет' + (ошибки.length ? ' — ' + ошибки.join(' | ') : ''));
  await контекст.close();
}

/* ---------- Поздний ответ «Создать игру» после «Назад» (замечание ревьюера) ----------
   Нажали «Создать игру» → до ответа сервера «Назад» → снова открыли экран.
   Кнопка обязана быть рабочей («Создать игру», не выключена), а поздний
   ответ старого открытия не должен её снова сломать. */
async function проверитьПоздныйОтвет(страница, имя) {
  const нажатие = await страница.evaluate(() => {
    const кнопка = document.getElementById('открытые-столы-создать');
    if (!кнопка) return null;
    window.__созданийВисит = 0;
    window.Сеть.создатьОткрытыйСтол = () => {
      window.__созданийВисит++;
      return new Promise((готово) => { window.__разрешитьСоздание = готово; });
    };
    кнопка.click();
    кнопка.click();   // второе нажатие, пока ответ в пути — должно отсечься
    return { выключена: кнопка.disabled, текст: кнопка.textContent.trim(), вызовов: window.__созданийВисит };
  });
  проверить(нажатие !== null, имя + ': кнопка «Создать игру» нашлась для сценария позднего ответа');
  if (!нажатие) return;
  проверить(нажатие.выключена && нажатие.текст === 'Создаём…',
    имя + ': пока ответ в пути, кнопка выключена и подписана «Создаём…» (вышло «' + нажатие.текст + '»)');
  проверить(нажатие.вызовов === 1, имя + ': двойное нажатие отсечено — запрос ушёл один раз (вышло ' + нажатие.вызовов + ')');

  await переоткрыть(страница, 'лобби-найти-игру');
  const послеПереоткрытия = await страница.evaluate(() => {
    const кнопка = document.getElementById('открытые-столы-создать');
    return кнопка ? { выключена: кнопка.disabled, текст: кнопка.textContent.trim() } : null;
  });
  проверить(Boolean(послеПереоткрытия) && !послеПереоткрытия.выключена && послеПереоткрытия.текст === 'Создать игру',
    имя + ': после «Назад» и нового открытия кнопка рабочая и подписана «Создать игру» (вышло ' +
    JSON.stringify(послеПереоткрытия) + ')');

  const послеОтвета = await страница.evaluate(async () => {
    if (typeof window.__разрешитьСоздание !== 'function') return null;
    window.__разрешитьСоздание({ ок: false, причина: 'проверка' });
    await new Promise((г) => setTimeout(г, 100));
    const кнопка = document.getElementById('открытые-столы-создать');
    return кнопка ? { выключена: кнопка.disabled, текст: кнопка.textContent.trim() } : null;
  });
  проверить(Boolean(послеОтвета) && !послеОтвета.выключена && послеОтвета.текст === 'Создать игру',
    имя + ': поздний ответ старого открытия кнопку не сломал (вышло ' + JSON.stringify(послеОтвета) + ')');
}

