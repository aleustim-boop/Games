async function подсунутьКопии(страница, копии) {
  await перехватить(страница, /\/js\/открытые-столы\.js(\?|$)|\/шашки\.html(\?|$)|\/style\.css(\?|$)|\/js\/сеть\.js(\?|$)/, (путь, запрос, адрес) => {
    const файл = /открытые-столы\.js/.test(адрес) ? копии.столы
      : (/style\.css/.test(адрес) ? копии.стили
      : (/\/сеть\.js/.test(адрес) ? копии.сеть : копии.шашки));
    if (файл.endsWith('.css')) {
      путь.fulfill({ status: 200, contentType: 'text/css; charset=utf-8', body: fs.readFileSync(файл, 'utf8') });
      return;
    }
    const тип = файл.endsWith('.js') ? 'application/javascript; charset=utf-8' : 'text/html; charset=utf-8';
    путь.fulfill({ status: 200, contentType: тип, body: fs.readFileSync(файл, 'utf8') });
  });
}

