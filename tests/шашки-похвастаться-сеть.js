'use strict';

/* Проверка «Похвастаться» в шашках: победа над ботом и победа по сети.
   Запуск: node tests/шашки-похвастаться-сеть.js [путь-к-копии-файла]
   Файл исполняется в песочнице vm с поддельной страницей и Telegram.
   Второй довод — путь к КОПИИ игры/шашки/шашки-похвастаться.js для ломающего запуска. */

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const корень = path.join(__dirname, '..');
const файл = process.argv[2] || path.join(корень, 'игры', 'шашки', 'шашки-похвастаться.js');
const код = fs.readFileSync(файл, 'utf8');

let всего = 0;
let провалов = 0;
function проверить(условие, что) {
  всего++;
  if (!условие) { провалов++; console.log('ПРОВАЛ: ' + что); }
  else console.log('ок: ' + что);
}

/** Страница с одной кнопкой; Сеть.похвастаться запоминает, что ей прислали. */
function собрать(вТелеграме) {
  const классы = new Set(['скрыт']);
  const кнопка = {
    textContent: 'Похвастаться',
    disabled: false,
    classList: {
      add: (к) => классы.add(к),
      remove: (к) => классы.delete(к),
      contains: (к) => классы.has(к),
      toggle: (к, вкл) => { if (вкл) классы.add(к); else классы.delete(к); }
    },
    addEventListener: (имя, обработчик) => { кнопка.нажать = обработчик; }
  };
  const отправки = [];
  const окно = {
    Сеть: { похвастаться: (описание) => { отправки.push(описание); return Promise.resolve({ отправлено: true }); } },
    Telegram: вТелеграме ? { WebApp: { initData: 'x=1' } } : undefined,
    ШашкиРекорды: { серия: () => 3 }
  };
  окно.window = окно;
  окно.document = { getElementById: (ид) => (ид === 'кнопка-похвастаться' ? кнопка : null) };
  окно.setTimeout = () => 0;
  vm.runInNewContext(код, окно, { filename: файл });
  return { окно, кнопка, отправки, видна: () => !классы.has('скрыт') };
}

async function нажатьИВзять(с) {
  с.кнопка.нажать();
  await Promise.resolve();
  await Promise.resolve();
  return с.отправки[с.отправки.length - 1];
}

async function главное() {
  // 1. Победа над ботом — как раньше
  const бот = собрать(true);
  проверить(!!бот.окно.ШашкиПохвастаться, 'модуль ШашкиПохвастаться создан');
  бот.окно.ШашкиПохвастаться.показать({ победа: true, уровень: 'сложный' });
  проверить(бот.видна(), 'победа над ботом: кнопка видна');
  const оБот = await нажатьИВзять(бот);
  проверить(!!оБот, 'победа над ботом: описание ушло в Сеть.похвастаться');
  проверить(оБот && оБот.соперники === 'боты', 'победа над ботом: соперники — боты');
  проверить(оБот && оБот.уровень === 'сложный' && оБот.серия === 3, 'победа над ботом: уровень и серия переданы');
  проверить(оБот && оБот.слова === 'Победа в шашках над сложным ботом — уже 3 подряд. Сыграем?', 'победа над ботом: текст как раньше');

  // 2. Победа по сети — люди
  const сеть = собрать(true);
  сеть.окно.ШашкиПохвастаться.показать({ победа: true, уровень: 'обычный', сеть: true });
  проверить(сеть.видна(), 'победа по сети: кнопка видна');
  const оСеть = await нажатьИВзять(сеть);
  проверить(!!оСеть, 'победа по сети: описание ушло в Сеть.похвастаться');
  проверить(оСеть && оСеть.соперники === 'люди', 'победа по сети: соперники — люди, не боты');
  проверить(оСеть && оСеть.игра === 'шашки' && оСеть.исход === 'победа' && оСеть.игроков === 2, 'победа по сети: игра, исход, игроков');
  проверить(оСеть && оСеть.слова === 'Победа в шашках с другом. Сыграем?', 'победа по сети: слова без «бота»');

  // 3. После сетевой победы новая партия с ботом снова «боты»
  сеть.окно.ШашкиПохвастаться.показать({ победа: true, уровень: 'лёгкий' });
  const оПосле = await нажатьИВзять(сеть);
  проверить(оПосле && оПосле.соперники === 'боты', 'после сетевой партии бот снова «боты»');

  // 4. Поражение — кнопки нет (и над ботом, и по сети)
  const пораж = собрать(true);
  пораж.окно.ШашкиПохвастаться.показать({ победа: false, уровень: 'обычный' });
  проверить(!пораж.видна(), 'поражение от бота: кнопки нет');
  пораж.окно.ШашкиПохвастаться.показать({ победа: false, уровень: 'обычный', сеть: true });
  проверить(!пораж.видна(), 'поражение по сети: кнопки нет');

  // 5. Вне Telegram — кнопки нет даже после победы
  const вне = собрать(false);
  вне.окно.ШашкиПохвастаться.показать({ победа: true, сеть: true });
  проверить(!вне.видна(), 'вне Telegram: кнопки нет');

  // 6. «Спрятать» прячет
  сеть.окно.ШашкиПохвастаться.показать({ победа: true, сеть: true });
  сеть.окно.ШашкиПохвастаться.спрятать();
  проверить(!сеть.видна(), 'спрятать: кнопка скрыта');

  console.log('Итого проверок: ' + всего + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
}

главное().catch((ошибка) => {
  console.log('ПРОВАЛ: проверка упала — ' + ошибка.message);
  console.log('Итого проверок: ' + (всего + 1) + ', провалов: ' + (провалов + 1));
  process.exit(1);
});
