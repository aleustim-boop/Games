const кость = (a, b) => П.КОСТИ.findIndex(к => к[0] === Math.min(a, b) && к[1] === Math.max(a, b));
const снимок = п => JSON.stringify(п.игра);
const номер = (п, ключ) => п.игроки.indexOf(ключ);

/* Сходить за место его СОБСТВЕННЫМ ходом (как человек с экрана), пока очередь
   не уйдёт от него: взял из базара — кладёт дальше. */
function сходитьСам(п, ключ) {
  for (let шаг = 0; шаг < 3 && Д.чейХод(п) === ключ; шаг++) {
    const ход = п.игра.фаза === 'итог' ? { действие: 'раунд' } : Б.ход(П.вид(п.игра, номер(п, ключ)), 'обычный');
    const ответ = Д.сделатьХод(п, ключ, ход);
    if (!ответ.принято) return ответ;
  }
  return { принято: true };
}

/* Стол, где у ходящего нет ни одной подходящей кости: на столе один дубль 6:6. */
function столБезПодходящей(базар) {
  const п = новаяПартия(3);
  const g = п.игра, i = g.ход;
  g.цепь = [{ id: кость(6, 6), a: 6, b: 6, кто: (i + 1) % 3 }];
  g.руки[i] = [кость(0, 0), кость(1, 2)];
  g.базар = базар;
  g.пасы = 0;
  return п;
}

