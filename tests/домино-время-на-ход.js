/* Копия лежит в другой папке — относительные require переписываем на полные пути. */
function сделатьКопию(папка, поломка) {
  const текст = fs.readFileSync(НАСТОЯЩИЙ, 'utf8');
  const сколько = текст.split(поломка.было).length - 1;
  if (сколько !== 1) return null;
  const испорчено = текст.replace(поломка.было, поломка.стало)
    .replace(/require\('(\.{1,2}\/[^']+)'\)/g, (_, путь) => 'require(' + JSON.stringify(path.resolve(path.dirname(НАСТОЯЩИЙ), путь)) + ')');
  const файл = path.join(папка, 'домино-' + ПОЛОМКИ.indexOf(поломка) + '.js');
  fs.writeFileSync(файл, испорчено);
  return файл;
}

function ломающиеЗапуски() {
  console.log('Часть 3: ломающие запуски на копии');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'домино-время-'));
  let строкаНеНашлась = false;
  try {
    for (const поломка of ПОЛОМКИ) {
      const файл = сделатьКопию(папка, поломка);
      if (!файл) {
        console.log('  НЕ НАШЛАСЬ строка для порчи ' + поломка.имя + ': ' + поломка.было);
        строкаНеНашлась = true;
        continue;
      }
      const итог = spawnSync(process.execPath, [__filename, '--модуль', файл], { encoding: 'utf8', timeout: 60000 });
      const вывод = (итог.stdout || '') + (итог.stderr || '');
      const строкаИтога = (вывод.match(/Итого проверок: (\d+), провалов: (\d+)/) || []);
      const покраснела = итог.status === 1 && Number(строкаИтога[2]) > 0;
      проверка('ломающий запуск ' + поломка.имя + ' краснеет', () => {
        assert.ok(покраснела, 'код ' + итог.status + ', ' + (строкаИтога[0] || 'итога нет') + '\n' + вывод.slice(-600));
        if (поломка.провалит) {
          const красные = вывод.split('\n').filter(с => с.includes('ПРОВАЛ  '));
          assert.ok(красные.some(с => с.includes(поломка.провалит)), 'покраснело не то: нужна «' + поломка.провалит + '», красные: ' + красные.join(' | ').slice(0, 300));
        }
      });
      if (покраснела) console.log('          (' + строкаИтога[0] + ')');
    }
  } finally {
    fs.rmSync(папка, { recursive: true, force: true });
  }
  return строкаНеНашлась;
}

