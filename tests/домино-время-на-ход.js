/* ---------- Часть 2. Настоящая комната с настоящими будильниками ---------- */

const пауза = мс => new Promise(r => setTimeout(r, мс));
async function дождаться(условие, мс) {
  const конец = Date.now() + мс;
  while (Date.now() < конец) { if (условие()) return true; await пауза(5); }
  return условие();
}

async function частьКомнаты() {
  console.log('Часть 2: комната');
  Д.сейчас = настоящиеЧасы;
  Д.подменитьСрокНаХодДляПроверки();
  const комнаты = require(path.join(КОРЕНЬ, 'server', 'комнаты'));

  function собратьСтол(мест) {
    const создано = комнаты.создатьКомнату('127.0.0.1', { игра: 'домино', имя: 'Анна', мест, цельДомино: 50 });
    assert.equal(создано.ок, true, создано.причина);
    const пропуска = [создано.пропуск];
    for (let k = 1; k < мест; k++) {
      const вход = комнаты.войтиВКомнату(создано.код, { имя: 'Гость ' + k });
      assert.equal(вход.ок, true, вход.причина);
      пропуска.push(вход.пропуск);
    }
    const хозяин = комнаты.найтиИгрока(создано.код, пропуска[0]);
    const комната = хозяин.комната;
    if (комната.этап !== 'игра') {
      const ответ = комнаты.сделатьХод(комната, хозяин.ктоЯ, { действие: 'начать' });
      assert.equal(ответ.принято, true, ответ.причина);
    }
    assert.equal(комната.этап, 'игра');
    return комната;
  }
  const пометки = комната => Object.values(комната.игроки).filter(м => м && (м.ушёл || м.этоБот)).length;

  const двое = собратьСтол(2);
  проверка('комната на двоих: будильник просрочки не заведён', () => {
    assert.ok(!двое.таймерПросрочки);
  });
  комнаты.удалитьКомнату(двое.код);

  const трое = собратьСтол(3);
  проверка('комната на троих: будильник просрочки заведён', () => {
    assert.ok(трое.таймерПросрочки);
  });
  комнаты.удалитьКомнату(трое.код);

  /* Короткий срок: первый будильник сработает сам. Дальше всё синхронно —
     пока идёт наш код, будильник комнаты сработать не может. */
  Д.подменитьСрокНаХодДляПроверки(0.3);
  const стол = собратьСтол(3);
  const п = стол.партия;
  const первый = Д.чейХод(п);
  const сработало = await дождаться(() => п.игра.последнее && п.игра.последнее.кто === номер(п, первый), 3000);

  проверка('комната: срок вышел — ход за просрочившего сделан, событие «ход-по-времени»', () => {
    assert.ok(сработало, 'будильник не сходил за первого');
    assert.equal(стол.событие.что, 'ход-по-времени');
    assert.equal(стол.событие.кто, первый);
    assert.notEqual(Д.чейХод(п), первый);
  });

  проверка('комната: просрочивший не помечен ушедшим и не отдан боту', () => {
    assert.ok(стол.игроки[первый], 'места просрочившего нет за столом');
    assert.ok(!стол.игроки[первый].ушёл);
    assert.ok(!стол.игроки[первый].этоБот);
    assert.equal(пометки(стол), 0);
  });

  проверка('комната: соседи после просрочки видят только свою руку', () => {
    for (const ключ of п.игроки.filter(к => к !== первый)) {
      const вид = комнаты.показатьИгроку(стол, ключ);
      const д = (вид.состояние || вид).домино;
      assert.equal(д.руки, null);
      assert.deepEqual(д.рука, п.игра.руки[номер(п, ключ)]);
    }
  });

  проверка('комната: свой следующий ход просрочивший делает сам', () => {
    for (let круг = 0; круг < 9 && Д.чейХод(п) !== первый; круг++) {
      const ключ = Д.чейХод(п);
      for (let шаг = 0; шаг < 3 && Д.чейХод(п) === ключ; шаг++) {
        const ход = Б.ход(П.вид(п.игра, номер(п, ключ)), 'обычный');
        assert.equal(комнаты.сделатьХод(стол, ключ, ход).принято, true);
      }
    }
    assert.equal(Д.чейХод(п), первый);
    const ход = Б.ход(П.вид(п.игра, номер(п, первый)), 'обычный');
    const ответ = комнаты.сделатьХод(стол, первый, ход);
    assert.equal(ответ.принято, true, ответ.причина);
    assert.equal(п.игра.последнее.кто, номер(п, первый));
  });

  /* Нулевой срок: дальше каждый ход делает будильник — матч обязан
     дойти до конца сам, без зависания и без пометок у людей. */
  Д.подменитьСрокНаХодДляПроверки(0);
  const кончилась = await дождаться(() => стол.этап !== 'игра', 15000);
  проверка('комната: матч одними просрочками доходит до конца', () => {
    assert.ok(кончилась, 'матч встал: ' + JSON.stringify({ этап: стол.этап, фаза: п.игра.фаза, ход: п.игра.ход }));
    assert.equal(стол.этап, 'конец');
    assert.equal(п.завершена, true);
    assert.ok(!стол.таймерПросрочки);
  });
  проверка('комната: после матча никто не помечен ушедшим или ботом', () => {
    assert.equal(пометки(стол), 0);
  });
  комнаты.удалитьКомнату(стол.код);
  Д.подменитьСрокНаХодДляПроверки();
}

