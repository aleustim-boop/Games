#!/usr/bin/env node
'use strict';

/* =====================================================================
   СЕТЕВОЙ ИТОГ «ПО КРУГУ» — новое поле вид.поКругу в видДляИгрока.

   Что проверяет (штаб/план-дурак-вечный-круг.md, этап 2 «Сеть»).
   Партия, зашедшая по кругу (расклад повторился трижды), кончается сама:
   правила (игры/дурак/game.js, другой этап) ставят партия.завершена = true,
   партия.поКругу = true, партия.проигравшие/результат — как при обычном
   конце, а при равенстве карт ещё и партия.ничья = true. Эта проверка
   не опирается на код game.js совсем — она собирает объект партии сама,
   ровно так, как это сделали бы правила, и смотрит, что дальше с ним
   делает сетевой слой:

     1) видДляИгрока каждому месту отдаёт честный вид.поКругу: true, когда
        партия.поКругу === true, и false (а не отсутствие поля — «клиенту
        не верим», см. .claude/rules/сервер.md), когда его нет вовсе;
     2) итог («победа»/«поражение»/«ничья») при поКругу — тот же самый,
        что дал бы обычный конец с тем же раскладом проигравших;
     3) ничья по кругу (партия.ничья = true) доезжает до рейтинга как
        ничья, а не как победа всех: server/комнаты.js:застольеДляРейтинга
        (через неё же считает и ничьяВПартии) обязана дать ничья: true,
        победил: false всем сидящим.

   КАК ПРОВЕРЯЕМ. Партия собирается через server/партия-по-сети.js:
   начатьПартию (тот же путь, каким комната раздаёт карты), без комнаты
   и без HTTP — так же, как tests/кто-положил-карту-сервер.js. Дальше
   поля завершена/поКругу/проигравшие/результат/ничья проставляются
   вручную — ровно то, что сделали бы правила. Для проверки рейтинга
   комната не поднимается целиком (это отдельный этап и лишние
   зависимости вроде рейтинг.js), а собирается минимальный узнаваемый
   объект «комната» — ровно те поля, что читает застольеДляРейтинга.

   ЛОМАЮЩИЙ ЗАПУСК: node tests/сеть-итог-по-кругу.js --сломать
   Копия server/ и js/ — во временной папке (os.tmpdir()), боевые файлы
   не трогаются. В копии server/партия-по-сети.js строка, которая пишет
   вид.поКругу, вырезается — сеть-модуль подгружается ИЗ КОПИИ, и первая
   же проверка «поКругу true» обязана провалиться. Строка для порчи не
   нашлась — значит код изменился, и проверка честно останавливается
   (exit 2), а не молчит с нулём найденного.

   Запуск:
     node tests/сеть-итог-по-кругу.js             обычный прогон, всё зелёное
     node tests/сеть-итог-по-кругу.js --сломать   копия без вид.поКругу — обязана покраснеть
   Выход 0 — провалов нет, 1 — есть провал, 2 — ломать было нечего (код изменился).
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const СЛОМАТЬ = process.argv.includes('--сломать');

/** Строка, которая пишет вид.поКругу в server/партия-по-сети.js — вырезаем дословно. */
function испортитьКопию(путьКСети) {
  const исходник = fs.readFileSync(путьКСети, 'utf8');
  const шаблон = /вид\.поКругу\s*=\s*партия\.поКругу\s*===\s*true;/;
  if (!шаблон.test(исходник)) {
    console.log('  БЕДА ломать нечего: строка «вид.поКругу = ...» в server/партия-по-сети.js не найдена — код изменился, поправьте tests/сеть-итог-по-кругу.js');
    process.exit(2);
  }
  const испорчено = исходник.replace(шаблон,
    '/* ИСПОРЧЕНО ПРОВЕРКОЙ tests/сеть-итог-по-кругу.js --сломать: поле вид.поКругу больше не пишется */');
  fs.writeFileSync(путьКСети, испорчено, 'utf8');
}

/** Своя копия server/ и js/ во временной папке — боевой код не трогаем. */
function подготовитьСломаннуюКопию() {
  const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'сеть-итог-по-кругу-'));
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(врем, 'server'), { recursive: true });
  require('./пути-проекта.js').скопироватьКод(КОРЕНЬ, врем, 'js');
  испортитьКопию(path.join(врем, 'server', 'партия-по-сети.js'));
  return врем;
}

const ПАПКА = СЛОМАТЬ ? подготовитьСломаннуюКопию() : КОРЕНЬ;
if (СЛОМАТЬ) {
  console.log('Ломающий прогон: копия server/партия-по-сети.js без вид.поКругу — ждём провала.');
  process.on('exit', function () {
    try { fs.rmSync(ПАПКА, { recursive: true, force: true }); } catch (сбой) { /* не страшно */ }
  });
}

// Сеть-слой берём из проверяемой папки (боевой или испорченной копии).
const сеть = require(path.join(ПАПКА, 'server', 'партия-по-сети.js'));
// Рейтинговый путь — всегда настоящий: ломающий запуск портит только поКругу,
// а не подсчёт ничьей, поэтому комнаты.js берём с диска проекта как есть.
const комнаты = require(path.join(КОРЕНЬ, 'server', 'комнаты.js'));

console.log('Сеть-слой из: ' + ПАПКА);

let проверок = 0;
let провалов = 0;
function проверить(условие, что) {
  проверок++;
  if (условие) {
    console.log('  ✓ ' + что);
  } else {
    провалов++;
    console.log('  ✗ ПРОВАЛ: ' + что);
  }
}

const [А, Б] = сеть.МЕСТА.slice(0, 2);

/** Новая партия вдвоём — тем же путём, каким её раздаёт комната. */
function новаяПартия() {
  return сеть.начатьПартию(null, { игроки: [А, Б] });
}

// Telegram-номера мест мока — застольеДляРейтинга кладёт их в поле «номер»
// (это НЕ номер места за столом, а именно telegram-id игрока).
const ТЕЛЕГРАМ_А = 501001;
const ТЕЛЕГРАМ_Б = 501002;

/** Минимальный объект «комната» — ровно те поля, что читает застольеДляРейтинга. */
function мокКомната(партия) {
  return {
    мест: 2,
    парами: false,
    переводной: false,
    игра: 'дурак',
    уровеньБотов: 3,
    игроки: {
      [А]: { телеграм: ТЕЛЕГРАМ_А, имя: 'Игрок А', этоБот: false, сдался: false },
      [Б]: { телеграм: ТЕЛЕГРАМ_Б, имя: 'Игрок Б', этоБот: false, сдался: false }
    },
    партия: партия
  };
}

function застольеПоТелеграму(застолье, телеграм) {
  return застолье.find(function (строка) { return строка.номер === телеграм; }) || null;
}

/* ---------------------------------------------------------------------
   1) Обычный конец (без поКругу) — эталон, с ним будем сравнивать итог.
   --------------------------------------------------------------------- */
console.log('\n1) Обычный конец: А остался дураком, поКругу не ставили вовсе');
const партияОбычная = новаяПартия();
партияОбычная.завершена = true;
партияОбычная.проигравшие = [А];
партияОбычная.результат = А;

const видАОбычный = сеть.видДляИгрока(партияОбычная, А, {});
const видБОбычный = сеть.видДляИгрока(партияОбычная, Б, {});
проверить(видАОбычный.поКругу === false, 'у А поКругу === false (честное значение, не отсутствие поля)');
проверить(видБОбычный.поКругу === false, 'у Б поКругу === false');
проверить(видАОбычный.итог === 'поражение', 'у А (дурака) обычный итог — поражение');
проверить(видБОбычный.итог === 'победа', 'у Б обычный итог — победа');

/* ---------------------------------------------------------------------
   2) Конец по кругу, тот же расклад — итог совпадает с обычным концом.
   --------------------------------------------------------------------- */
console.log('\n2) Итог по кругу: тот же расклад (А — дурак), поКругу = true');
const партияПоКругу = новаяПартия();
партияПоКругу.завершена = true;
партияПоКругу.поКругу = true;
партияПоКругу.проигравшие = [А];
партияПоКругу.результат = А;

const видАПоКругу = сеть.видДляИгрока(партияПоКругу, А, {});
const видБПоКругу = сеть.видДляИгрока(партияПоКругу, Б, {});
проверить(видАПоКругу.поКругу === true, 'у А вид.поКругу === true');
проверить(видБПоКругу.поКругу === true, 'у Б вид.поКругу === true');
проверить(видАПоКругу.завершена === true, 'у А вид.завершена === true, как при обычном конце');
проверить(видАПоКругу.итог === видАОбычный.итог, 'итог по кругу у А совпадает с итогом обычного конца (поражение)');
проверить(видБПоКругу.итог === видБОбычный.итог, 'итог по кругу у Б совпадает с итогом обычного конца (победа)');

const застольеПоКругу = комнаты.застольеДляРейтинга(мокКомната(партияПоКругу));
const рейтингА = застольеПоТелеграму(застольеПоКругу, ТЕЛЕГРАМ_А);
const рейтингБ = застольеПоТелеграму(застольеПоКругу, ТЕЛЕГРАМ_Б);
проверить(Boolean(рейтингА) && рейтингА.победил === false && рейтингА.ничья === false,
  'рейтинг: А (дурак по кругу) не победил и это не ничья');
проверить(Boolean(рейтингБ) && рейтингБ.победил === true && рейтингБ.ничья === false,
  'рейтинг: Б (не дурак по кругу) победил');

/* ---------------------------------------------------------------------
   3) Ничья по кругу: карт поровну, дурака нет.
   --------------------------------------------------------------------- */
console.log('\n3) Ничья по кругу: партия.ничья = true, проигравших нет');
const партияНичьяПоКругу = новаяПартия();
партияНичьяПоКругу.завершена = true;
партияНичьяПоКругу.поКругу = true;
партияНичьяПоКругу.ничья = true;
партияНичьяПоКругу.проигравшие = [];
партияНичьяПоКругу.результат = 'ничья';

const видАНичья = сеть.видДляИгрока(партияНичьяПоКругу, А, {});
const видБНичья = сеть.видДляИгрока(партияНичьяПоКругу, Б, {});
проверить(видАНичья.поКругу === true, 'у А вид.поКругу === true при ничьей по кругу');
проверить(видБНичья.поКругу === true, 'у Б вид.поКругу === true при ничьей по кругу');
проверить(видАНичья.итог === 'ничья', 'у А итог — ничья');
проверить(видБНичья.итог === 'ничья', 'у Б итог — ничья');

// Ноль найденного — тоже провал: застолье обязано вернуть ровно две строки.
const застольеНичья = комнаты.застольеДляРейтинга(мокКомната(партияНичьяПоКругу));
проверить(застольеНичья.length === 2, 'рейтинг видит обе строки застолья (ничья по кругу)');
const рейтингАНичья = застольеПоТелеграму(застольеНичья, ТЕЛЕГРАМ_А);
const рейтингБНичья = застольеПоТелеграму(застольеНичья, ТЕЛЕГРАМ_Б);
проверить(Boolean(рейтингАНичья) && рейтингАНичья.ничья === true && рейтингАНичья.победил === false,
  'рейтинг: у А ничья === true, победил === false (не победа всех)');
проверить(Boolean(рейтингБНичья) && рейтингБНичья.ничья === true && рейтингБНичья.победил === false,
  'рейтинг: у Б ничья === true, победил === false (не победа всех)');

/* ---------------------------------------------------------------------
   4) Партия ещё не кончилась — поле честно false, не мусор из прошлой игры.
   --------------------------------------------------------------------- */
console.log('\n4) Партия идёт, поКругу нет вовсе — честный false у обоих мест');
const партияЖивая = новаяПартия();
const видАЖивая = сеть.видДляИгрока(партияЖивая, А, {});
const видБЖивая = сеть.видДляИгрока(партияЖивая, Б, {});
проверить(видАЖивая.поКругу === false, 'у А поКругу === false, пока партия идёт');
проверить(видБЖивая.поКругу === false, 'у Б поКругу === false, пока партия идёт');

/* ---------------------------------------------------------------------- */
console.log('');
console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
process.exit(провалов > 0 ? 1 : 0);
