#!/usr/bin/env node
'use strict';

/* =====================================================================
   ПРОВЕРКА: js/сеть.js подключена на каждой странице игры

   Правило владельца: друзья видят «в сети» того, кто в игре.
   Отметку ставит js/сеть.js, значит он обязан быть подключен на
   странице КАЖДОЙ игры — для сети и локальных игр одинаково.

   Что проверяем:
   1. Реестр игр загружается и не пуст
   2. Для каждой игры из реестра:
      - файл её страницы существует
      - в файле есть подключение js/сеть.js
      - подключение ровно одно (не забыли, не продублировали)
      - версия в ?v= совпадает с версией в index.html

   Запуск:
       node tests/сеть-на-каждой-странице.js                  — обычная проверка
       node tests/сеть-на-каждой-странице.js --корень=<папка> — другой корень
       node tests/сеть-на-каждой-странице.js --сломать        — ломающий запуск

   Ломающий запуск портит КОПИИ во временной папке, настоящие файлы
   не трогаются. Проверка обязана покраснеть на отсутствии сеть.js.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

const ПРОЕКТ = path.join(__dirname, '..');

/**
 * Прочитать файл и вернуть содержимое, или null, если файла нет.
 */
function прочитать(полнойПуть) {
  return fs.existsSync(полнойПуть) ? fs.readFileSync(полнойПуть, 'utf8') : null;
}

/**
 * Извлечь версию js/сеть.js из html (первое совпадение ?v=...).
 * Возвращает версию или null, если подключение не найдено.
 */
function найтиВерсию(html) {
  const чистый = безКомментариев(html);
  const образец = /js\/сеть\.js\?v=([^\s"'>;]+)/;
  const найдено = чистый.match(образец);
  return найдено ? найдено[1] : null;
}

/**
 * Удалить комментарии html и js из текста.
 */
function безКомментариев(текст) {
  return текст
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:'"\\])\/\/[^\n]*/g, '$1');
}

/**
 * Подсчитать количество подключений js/сеть.js в html.
 * Ищет только в тегах <script src="js/сеть.js...
 */
function подсчитатьПодключения(html) {
  const чистый = безКомментариев(html);
  const образец = /<script[^>]*src="js\/сеть\.js(?:\?[^\s"'>;]*)?"[^>]*><\/script>/g;
  const найденное = чистый.match(образец);
  return найденное ? найденное.length : 0;
}

/**
 * Проверить один корень (проект или копию).
 * Возвращает { проверок, провалы }.
 */
function проверитьКорень(КОРЕНЬ, тихо) {
  const итог = { проверок: 0, провалы: [] };

  function сказать(т) { if (!тихо) console.log(т); }
  function проверить(условие, текстПровала) {
    итог.проверок++;
    if (!условие) {
      итог.провалы.push(текстПровала);
      сказать('ПРОВАЛ: ' + текстПровала);
    }
    return условие;
  }

  /* ---- Реестр игр ---- */
  let реестр = [];
  try {
    const путь = path.join(КОРЕНЬ, 'js', 'игры-реестр.js');
    delete require.cache[path.resolve(путь)];
    реестр = require(путь).все();
  } catch (ошибка) {
    проверить(false, 'не читается js/игры-реестр.js: ' + ошибка.message);
    сказать('Итого проверок: ' + итог.проверок + ', провалов: ' + итог.провалы.length);
    return итог;
  }

  проверить(реестр.length > 0, 'реестр игр пуст — нечего проверять');
  if (реестр.length === 0) {
    сказать('Итого проверок: ' + итог.проверок + ', провалов: ' + итог.провалы.length);
    return итог;
  }

  /* ---- Версия в index.html ---- */
  const индексПуть = path.join(КОРЕНЬ, 'index.html');
  const индекс = прочитать(индексПуть);

  проверить(индекс !== null, 'файл index.html не найден');

  let ожидаемаяВерсия = null;
  if (индекс !== null) {
    ожидаемаяВерсия = найтиВерсию(индекс);
    проверить(ожидаемаяВерсия !== null, 'в index.html не найдено подключение js/сеть.js?v=');
  }

  if (!ожидаемаяВерсия) {
    сказать('Итого проверок: ' + итог.проверок + ', провалов: ' + итог.провалы.length);
    return итог;
  }

  сказать('Версия js/сеть.js в index.html: ' + ожидаемаяВерсия);
  сказать('Игр в реестре: ' + реестр.length + '\n');

  /* ---- Проверить каждую игру ---- */
  реестр.forEach(function (и) {
    const страница = и.страница;
    const ключ = и.ключ;

    if (!страница) {
      проверить(false, 'игра «' + ключ + '» не имеет страницы в реестре');
      сказать('ОК     ' + ключ + ' (страница не указана, проверка пропущена)');
      return;
    }

    const путь = path.join(КОРЕНЬ, страница);
    const содержимое = прочитать(путь);

    if (!проверить(содержимое !== null, 'страница ' + страница + ' не найдена (игра ' + ключ + ')')) {
      сказать('ОШИБКА ' + ключ + ' (' + страница + ') — файл не существует');
      return;
    }

    /* Подсчитать подключения сеть.js */
    const кол = подсчитатьПодключения(содержимое);

    if (!проверить(кол > 0, 'в ' + страница + ' не найдено подключение js/сеть.js (игра ' + ключ + ')')) {
      сказать('ошибка  ' + ключ + ' (' + страница + ') — сеть.js не подключена');
      return;
    }

    if (!проверить(кол === 1, 'в ' + страница + ' найдено ' + кол + ' подключений js/сеть.js вместо одного (игра ' + ключ + ')')) {
      сказать('ошибка  ' + ключ + ' (' + страница + ') — подключений ' + кол + ' вместо 1');
      return;
    }

    /* Проверить версию */
    const версия = найтиВерсию(содержимое);

    if (!проверить(версия !== null, 'в ' + страница + ' подключение js/сеть.js без версии ?v= (игра ' + ключ + ')')) {
      сказать('ошибка  ' + ключ + ' (' + страница + ') — версия не указана');
      return;
    }

    if (!проверить(версия === ожидаемаяВерсия,
      'в ' + страница + ' версия ' + версия + ', ожидали ' + ожидаемаяВерсия + ' (игра ' + ключ + ')')) {
      сказать('ошибка  ' + ключ + ' (' + страница + ') — версия ' + версия + ', в index.html ' + ожидаемаяВерсия);
      return;
    }

    /* Всё в порядке */
    сказать('ОК     ' + ключ + ' (' + страница + ')');
  });

  сказать('');
  сказать('Итого проверок: ' + итог.проверок + ', провалов: ' + итог.провалы.length);
  return итог;
}

/* ===================== Ломающий запуск ===================== */

/**
 * Копия index.html и одной страницы во временной папке.
 */
function копияДляЛомания() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'сеть-сломать-'));

  /* Копируем index.html */
  const индексИсточник = path.join(ПРОЕКТ, 'index.html');
  const индексКопия = path.join(папка, 'index.html');
  fs.copyFileSync(индексИсточник, индексКопия);

  /* Копируем js/игры-реестр.js */
  fs.mkdirSync(path.join(папка, 'js'));
  const реестрИсточник = path.join(ПРОЕКТ, 'js', 'игры-реестр.js');
  const реестрКопия = path.join(папка, 'js', 'игры-реестр.js');
  fs.copyFileSync(реестрИсточник, реестрКопия);

  return папка;
}

/**
 * Найти первую страницу игры (не vitrine), скопировать её.
 * Возвращает { папка, страница, полнойПуть }.
 */
function найтиИКопироватьСтраницу(папка) {
  const реестр = require(path.join(папка, 'js', 'игры-реестр.js')).все();

  /* Ищем первую страницу, которая не витрина */
  let страница = null;
  for (let и of реестр) {
    if (и.страница && и.страница !== 'index.html') {
      страница = и.страница;
      break;
    }
  }

  if (!страница) {
    throw new Error('не найдено ни одной страницы игры (кроме витрины)');
  }

  const источник = path.join(ПРОЕКТ, страница);
  const назначение = path.join(папка, страница);

  /* Создать папку, если нужно (для вложенных путей) */
  const папкаСтраницы = path.dirname(назначение);
  if (!fs.existsSync(папкаСтраницы)) {
    fs.mkdirSync(папкаСтраницы, { recursive: true });
  }

  fs.copyFileSync(источник, назначение);

  return { папка, страница, полнойПуть: назначение };
}

function ломающийЗапуск() {
  console.log('Ломающий запуск --сломать: портим КОПИИ во временной папке.\n');

  const копия = копияДляЛомания();
  let итог;

  try {
    const файл = найтиИКопироватьСтраницу(копия);

    /* Вырезать подключение сеть.js из копии страницы */
    const содержимое = fs.readFileSync(файл.полнойПуть, 'utf8');
    const безСети = содержимое.replace(/<script[^>]*src="js\/сеть\.js[^"]*"[^>]*><\/script>\n?/g, '');

    if (безСети === содержимое) {
      console.log('ВНИМАНИЕ: в ' + файл.страница + ' не найдено подключение js/сеть.js для удаления');
      console.log('Ломающий прогон не смог испортить файл — проверка может быть слепа\n');
    } else {
      fs.writeFileSync(файл.полнойПуть, безСети, 'utf8');
      console.log('Удалена строка подключения js/сеть.js из ' + файл.страница);
    }

    /* Прогнать проверку на испорченной копии */
    console.log('Прогон проверки на поддельном корне: ' + копия + '\n');
    итог = проверитьКорень(копия, false);
  } finally {
    /* Очистить временную папку */
    fs.rmSync(копия, { recursive: true, force: true });
  }

  /* Проверить, что обнаружились провалы */
  if (итог.провалы.length > 0) {
    console.log('\nЛОМАЮЩИЙ ПРОГОН ПОКРАСНЕЛ, как и должен.');
    process.exit(1);
  } else {
    console.log('\nОШИБКА: ломающий прогон НЕ покраснел! Проверка может быть слепа.');
    process.exit(1);
  }
}

/* ===================== Главная программа ===================== */

if (process.argv.indexOf('--сломать') !== -1) {
  ломающийЗапуск();
} else {
  const довод = process.argv.find(function (а) { return а.indexOf('--корень=') === 0; });
  const корень = довод ? path.resolve(довод.slice('--корень='.length)) : ПРОЕКТ;

  console.log('Корень: ' + корень + '\n');

  const итог = проверитьКорень(корень, false);
  process.exit(итог.провалы.length ? 1 : 0);
}
