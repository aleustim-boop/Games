const спать = (мс) => new Promise((ф) => setTimeout(ф, мс));

async function новаяСтраница(браузер, ш, в) {
  const окно = await браузер.newContext({ viewport: { width: ш, height: в }, hasTouch: true, deviceScaleFactor: 2 });
  const страница = await окно.newPage();
  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
    if (/Failed to load resource/.test(м.text())) return;
    красные.push('консоль: ' + м.text());
  });
  await подготовитьПодделку(страница, { версия: '8.0', полныйЭкран: 'дают' });
  await страница.goto(АДРЕС);
  await спать(500);
  return { окно, страница, красные };
}

/** Тап по клетке доски по имени поля («c3», «d4»…) — так же, как в остальных стендах шашек. */
async function тапПоПолю(страница, поле) {
  await страница.evaluate((имя) => {
    const узел = document.querySelector('[data-поле="' + имя + '"]');
    if (узел) узел.click();
  }, поле);
}

/** Ход двумя касаниями. Пауза внутри короткая — тест успевает заглянуть
 *  на доску ПОСЛЕ хода человека, но ДО ответа бота (пауза перед его
 *  ходом — не меньше 450 мс, см. js/шашки-экран.js). */
async function сходить(страница, откуда, куда) {
  await тапПоПолю(страница, откуда);
  await спать(120);
  await тапПоПолю(страница, куда);
  await спать(150);
}

/** «125» → «02:05». */
function секундыИзТекста(текст) {
  const части = String(текст || '').split(':');
  if (части.length !== 2) return NaN;
  return Number(части[0]) * 60 + Number(части[1]);
}

/** Снимок плашки часов (видимость, активность, текст) по суффиксу «сверху»/«снизу». */
async function снимокЧасов(страница, суффикс) {
  return страница.evaluate((с) => {
    const узел = document.getElementById('часы-' + с);
    const текст = document.getElementById('часы-' + с + '-текст');
    return {
      видна: !!узел && узел.offsetParent !== null,
      активна: !!узел && узел.classList.contains('панель-игрока-шашек__часы--активны'),
      текст: текст ? текст.textContent : ''
    };
  }, суффикс);
}

async function снимокОбеихЧасов(страница) {
  return { сверху: await снимокЧасов(страница, 'сверху'), снизу: await снимокЧасов(страница, 'снизу') };
}

/** Кнопки под доской и плашка итога разом — то, что нужно проверить после сдачи/времени. */
async function снимокПослеИтога(страница) {
  return страница.evaluate(() => {
    const итог = document.getElementById('экран-итога');
    const причина = document.getElementById('причина-итога');
    const ничья = document.getElementById('кнопка-ничьей');
    const сдаться = document.getElementById('кнопка-сдаться');
    const отмена = document.getElementById('кнопка-отменить-ход');
    return {
      итогВиден: итог.classList.contains('экран--виден'),
      причина: причина ? причина.textContent : '',
      ничьяDisabled: ничья ? ничья.disabled : null,
      сдатьсяDisabled: сдаться ? сдаться.disabled : null,
      отменаDisabled: отмена ? отмена.disabled : null
    };
  });
}

