/** Вырезать тело функции «выйти(комната, ктоЯ, заМолчание, безСдачи)» из текста файла. */
function телоФункцииВыйти(текст) {
  const метка = 'function выйти(комната, ктоЯ, заМолчание, безСдачи)';
  const начало = текст.indexOf(метка);
  if (начало === -1) return null;
  const следующая = текст.indexOf('\nfunction ', начало + метка.length);
  return { текст: текст.slice(начало, следующая === -1 ? текст.length : следующая), начало: начало, конец: следующая === -1 ? текст.length : следующая };
}

/** Своя копия server/ и js/ во временной папке — боевой код не трогаем. */
function подготовитьКопию() {
  const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'выход-победителя-'));
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(врем, 'server'), { recursive: true });
  fs.cpSync(path.join(КОРЕНЬ, 'js'), path.join(врем, 'js'), { recursive: true });
  return врем;
}

/**
 * Испортить копию: если починка уже есть — глушим её и возвращаем старый баг.
 * Сейчас (30.09, после правки разработчика) починка живёт как отдельная
 * функция «ужеВнеИгры(комната, ктоЯ)», вызванная из тела «выйти()» — внутри
 * неё и сидит «правила.вИгре(партия, ктоЯ) === false». Портим по вызову
 * «ужеВнеИгры(...)» в теле «выйти()» (подменяем результат на false — «никто
 * никогда не вне игры»); если такого вызова там нет, пробуем более раннюю
 * возможную форму починки — прямой «правила.вИгре(...)» в теле «выйти()».
 * Не нашлось ни то, ни другое — чинить, скорее всего, ещё нечего вовсе.
 */
function испортитьКопию(путьККомнатам) {
  const исходник = fs.readFileSync(путьККомнатам, 'utf8');
  const тело = телоФункцииВыйти(исходник);
  if (тело === null) {
    console.log('БЕДА ломать нечего: функция «выйти(комната, ктоЯ, заМолчание, безСдачи)» в server/комнаты.js не найдена — код изменился, поправьте tests/выход-победителя-не-поражение.js');
    process.exit(2);
  }
  let испорченноеТело = null;
  if (/ужеВнеИгры\(комната, ктоЯ\)/.test(тело.текст)) {
    испорченноеТело = тело.текст.replace(/ужеВнеИгры\(комната, ктоЯ\)/g,
      '(false /* ИСПОРЧЕНО tests/выход-победителя-не-поражение.js --сломать: «вне игры» больше не проверяется */)');
  } else if (/правила\.вИгре\(/.test(тело.текст)) {
    испорченноеТело = тело.текст.replace(/правила\.вИгре\([^)]*\)/,
      '(true /* ИСПОРЧЕНО tests/выход-победителя-не-поражение.js --сломать: «вне игры» больше не проверяется */)');
  }
  if (испорченноеТело === null) {
    console.log('Ломать нечего: внутри «выйти()» нет ни «ужеВнеИгры(комната, ктоЯ)», ни «правила.вИгре(...)» — починка ревьюерской находки ещё не внесена.');
    console.log('На боевом server/комнаты.js обычный прогон этой проверки (без --сломать) должен быть красным — это и есть текущая поломка.');
    process.exit(2);
  }
  const испорчено = исходник.slice(0, тело.начало) + испорченноеТело + исходник.slice(тело.конец);
  fs.writeFileSync(путьККомнатам, испорчено, 'utf8');
}

