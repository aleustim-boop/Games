let номерАдреса = 0;
function новыйАдрес() {
  номерАдреса++;
  return '10.0.11.' + номерАдреса;
}

/** Стол на троих без пар: A хозяин, Б и В входят, A жмёт «Начать». */
function столНаТроих(база) {
  const создана = комнаты.создатьКомнату(новыйАдрес(), {
    имя: 'Игрок А', телеграм: база + 1, мест: 3, парами: false, игра: 'дурак'
  });
  if (!создана.ок) throw new Error('стол на троих не создался: ' + создана.причина);
  const входБ = комнаты.войтиВКомнату(создана.код, { имя: 'Игрок Б', телеграм: база + 2 });
  const входВ = комнаты.войтиВКомнату(создана.код, { имя: 'Игрок В', телеграм: база + 3 });
  if (!входБ.ок || !входВ.ок) throw new Error('не все трое вошли за стол');
  const A = комнаты.найтиИгрока(создана.код, создана.пропуск);
  const Б = комнаты.найтиИгрока(создана.код, входБ.пропуск);
  const В = комнаты.найтиИгрока(создана.код, входВ.пропуск);
  const начали = комнаты.сделатьХод(A.комната, A.ктоЯ, { действие: 'начать' });
  if (!начали.принято) throw new Error('партия втроём не началась: ' + начали.причина);
  return {
    комната: A.комната, код: создана.код,
    A: A.ктоЯ, Б: Б.ктоЯ, В: В.ктоЯ,
    номера: { A: база + 1, Б: база + 2, В: база + 3 }
  };
}

/** Карта из записи «6♣», «9♥» — тем же способом, что и tests/дурак-вечный-круг.js. */
function карта(запись) {
  const масть = запись.slice(-1);
  const имя = запись.slice(0, -1);
  return { масть: масть, имя: имя, вес: правила.ВСЕ_ДОСТОИНСТВА.indexOf(имя) + 2 };
}

/**
 * Подложить руки идущей партии вручную (приём tests/дурак-вечный-круг.js,
 * функция «собратьРасклад»), но на уже созданном столе комнаты — сохраняем
 * те же ключи мест, что комната уже раздала при «начать».
 *
 * рукиПоМестам — { местоКлюч: [запись, запись, ...] }. Место, для которого
 * список пуст, сразу же кладём в «выбывшие» — это и есть «уже скинул все
 * карты, вне игры» (js/game.js:вИгре смотрит именно на «выбывшие», не на
 * длину руки саму по себе).
 */
function подложитьРасклад(комната, козырь, рукиПоМестам, местоАтакиКлюч) {
  const местаПорядок = комната.партия.игроки.slice();
  const партия = правила.создатьПартию({ игроки: местаПорядок });
  const занятые = new Set();
  местаПорядок.forEach(function (место) {
    const записи = рукиПоМестам[место] || [];
    партия.руки[место] = записи.map(карта);
    for (const к of партия.руки[место]) занятые.add(к.имя + к.масть);
  });
  const все = правила.собратьКолоду(партия.размерКолоды);
  партия.отбой = все.filter(function (к) { return !занятые.has(к.имя + к.масть); });
  партия.колода = [];
  партия.стол = [];
  партия.пасы = [];
  партия.берёт = false;
  партия.подходов = 10;
  партия.козырь = козырь;
  партия.козырнаяКарта = все.filter(function (к) { return к.масть === козырь; })[0];
  партия.местоАтаки = местаПорядок.indexOf(местоАтакиКлюч);
  партия.выбывшие = местаПорядок.filter(function (место) { return (рукиПоМестам[место] || []).length === 0; });
  партия.завершена = false;
  комната.партия = партия;
  return { местаПорядок: местаПорядок };
}

function найтиВЗастолье(застолье, номер) {
  return (застолье || []).find(function (строка) { return строка.номер === номер; }) || null;
}

