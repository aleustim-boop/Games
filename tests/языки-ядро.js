/* Проверка ядра перевода js/языки.js (чистый node, без браузера).
   Запуск: node tests/языки-ядро.js
   Ломающий запуск: node tests/языки-ядро.js --сломать <временная папка>
   Он копирует js/языки.js и js/языки-общие.js в папку, портит КОПИЮ ядра
   (выключает перевод вложенных групп) и требует, чтобы проверка на ней покраснела.
   Настоящий файл не трогается. */
const fs = require('fs');
const path = require('path');
const корень = path.join(__dirname, '..');

const аргументы = process.argv.slice(2);
const номерСломать = аргументы.indexOf('--сломать');
const ломаем = номерСломать !== -1;

/* Подготовить папку с ядром: настоящая js/ или испорченная копия во временной папке. */
function папкаЯдра() {
  const настоящая = path.join(корень, 'js');
  if (!ломаем) return настоящая;
  const папка = аргументы[номерСломать + 1];
  if (!папка) { console.log('Не указана временная папка после --сломать'); process.exit(2); }
  fs.mkdirSync(папка, { recursive: true });
  const исходное = fs.readFileSync(path.join(настоящая, 'языки.js'), 'utf8');
  const вставка = 'return переводГруппы(значение, код);';
  if (!исходное.includes(вставка)) { console.log('Ломать нечего: в ядре нет строки перевода групп'); process.exit(2); }
  fs.writeFileSync(path.join(папка, 'языки.js'), исходное.replace(вставка, 'return значение;'));
  fs.copyFileSync(path.join(настоящая, 'языки-общие.js'), path.join(папка, 'языки-общие.js'));
  return папка;
}

const папка = папкаЯдра();
const Я = require(path.join(папка, 'языки.js'));
require(path.join(папка, 'языки-общие.js'));

let проверено = 0;
const провалы = [];
function требую(условие, описание) {
  проверено++;
  if (!условие) провалы.push(описание);
}
const естьКириллица = с => /[А-Яа-яЁё]/.test(с);

// (в) вложенные названия: «Рейтинг «Шашки»» — группа есть в словаре, значит переведена.
Я.добавить('Тестовая область|Тестова область|Test area\nЛес|Ліс|Wood\nГлина|Глина|Clay');
Я.добавитьШаблоны([[/^Ядро: (.+)$/, 'Ядро: $1', 'Core: $1']]);
требую(Я.текст('Ядро: Тестовая область', 'en') === 'Core: Test area', 'группа из словаря не переведена (en)');
требую(Я.текст('Ядро: Тестовая область', 'uk') === 'Ядро: Тестова область', 'группа из словаря не переведена (uk)');
требую(Я.текст('Ядро: Оля', 'en') === 'Core: Оля', 'имя игрока должно остаться как есть');
требую(Я.текст('Ядро: Лес × 1, Глина × 2', 'en') === 'Core: Wood × 1, Clay × 2', 'список «Слово × N» не переведён: ' + Я.текст('Ядро: Лес × 1, Глина × 2', 'en'));
требую(Я.текст('Ядро: Лес × 1, Оля × 2', 'en') === 'Core: Wood × 1, Оля × 2', 'неизвестная часть списка должна остаться');

// (а) память: тот же ответ второй раз; после добавить() новый ключ виден.
const первый = Я.текст('Совсем новая фраза ядра', 'en');
требую(первый === 'Совсем новая фраза ядра', 'непереведённая фраза должна вернуться как есть');
требую(Я.текст('Совсем новая фраза ядра', 'en') === первый, 'второй вызов дал другой ответ');
Я.добавить('Совсем новая фраза ядра|Зовсім нова фраза ядра|Brand new core phrase');
требую(Я.текст('Совсем новая фраза ядра', 'en') === 'Brand new core phrase', 'после добавить() память не сброшена');
Я.текст('Ещё одна фраза', 'en');
Я.добавитьШаблоны([[/^Ещё одна фраза$/, 'Ще одна фраза', 'Yet another phrase']]);
требую(Я.текст('Ещё одна фраза', 'en') === 'Yet another phrase', 'после добавитьШаблоны() память не сброшена');

// (г) «Рыба» на en — не «Fish» (в домино это закрытая игра).
требую(Я.текст('Рыба', 'en') !== 'Fish' && Я.текст('Рыба', 'en') === 'Blocked', '«Рыба» на en: ' + Я.текст('Рыба', 'en'));

// (д) «Вы забрали карты со стола — …» с общим словарём не содержит кириллицы.
for (const [фраза, код] of [['Вы забрали карты со стола — 10♣, 7♥', 'en'], ['Вы забрали карты со стола — 10♣, 7♥', 'uk'], ['Вы забрали карты со стола', 'en']]) {
  const ответ = Я.текст(фраза, код);
  // У украинского кириллица законна: проверяем, что русских слов не осталось.
  const плохо = код === 'en' ? естьКириллица(ответ) : /(?:карты|стола|со )/.test(ответ);
  требую(!плохо, '«' + фраза + '» (' + код + ') вышла полурусской: ' + ответ);
}

// (б) замер: 2000 непереведённых фраз при 2000 подставных шаблонах — повтор минимум в 5 раз быстрее.
const подставные = [];
for (let i = 0; i < 2000; i++) подставные.push([new RegExp('^Подставной шаблон номер ' + i + ' (.+)$'), 'х $1', 'x $1']);
Я.добавитьШаблоны(подставные);
const фразы = [];
for (let i = 0; i < 2000; i++) фразы.push('Непереведённая надпись ' + i);
function проход() {
  const начало = process.hrtime.bigint();
  for (const ф of фразы) Я.текст(ф, 'en');
  return Number(process.hrtime.bigint() - начало) / 1e6;
}
const первыйПроход = проход();
const повторныйПроход = Math.max(проход(), 0.05);
console.log('Замер: первый проход ' + первыйПроход.toFixed(1) + ' мс, повторный ' + повторныйПроход.toFixed(2) + ' мс, ускорение в ' + (первыйПроход / повторныйПроход).toFixed(0) + ' раз');
требую(первыйПроход / повторныйПроход >= 5, 'повторный проход не быстрее первого минимум в 5 раз');

if (проверено === 0) { console.log('ПРОВАЛ: не проверено ни одного случая'); process.exit(1); }
console.log('Итого проверок: ' + проверено + ', провалов: ' + провалы.length);
for (const п of провалы) console.log('  ПРОВАЛ: ' + п);

if (ломаем) {
  if (провалы.length === 0) { console.log('ЛОМАЮЩИЙ ЗАПУСК НЕ ПОКРАСНЕЛ — проверка бесполезна'); process.exit(1); }
  console.log('Ломающий запуск покраснел, как и должен');
  process.exit(0);
}
process.exit(провалы.length ? 1 : 0);
