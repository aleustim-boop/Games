/* Все тела ответов за весь прогон — под конец сверяем их разом на
   утечку номеров Telegram (см. общую проверку в конце файла). */
const собранныеТела = [];

function спросить(путь, тело) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН_АДРЕС, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (сбой) { разобрано = null; }
        собранныеТела.push(текст);
        готово({ код: ответ.statusCode, тело: разобрано, текст: текст });
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

/** Подписанный запрос от имени игрока к одной из дверей. */
function дверь(путь, кто, имя, довесок) {
  const тело = Object.assign({ initData: подписьИгрока(кто, имя) }, довесок || {});
  return спросить(путь, тело);
}

/* ---------------------------------------------------------------------
   Настоящие столы для зовущих — дверь /позвать сверяет код стола, и
   без настоящей комнаты любой зов отклонится на этой проверке раньше,
   чем дойдёт до ключа знакомого или друга. Один игрок — один стол.
   --------------------------------------------------------------------- */

const столыИгроков = new Map();

/** Настоящий стол этого игрока — создаёт при первом обращении. */
async function стол(кто, имя) {
  if (столыИгроков.has(кто)) return столыИгроков.get(кто);
  const ответ = await дверь('/создать', кто, имя);
  const запись = { код: (ответ.тело && ответ.тело.код) || '' };
  столыИгроков.set(кто, запись);
  return запись;
}

/** Позвать по ключу от имени этого игрока, с его настоящего стола. */
async function позвать(кто, имя, ключ) {
  const мойСтол = await стол(кто, имя);
  const ссылка = ссылкаЗаСтол(мойСтол.код);
  return дверь('/позвать', кто, имя, { ключ: ключ, ссылка: ссылка, код: мойСтол.код });
}

/** Найти запись друга/знакомого в списке по имени. */
function найтиПоИмени(список, имя) {
  return (список || []).find(function (запись) { return запись.имя === имя; });
}

/** Короткая пауза — нужна, чтобы обойти предел «не чаще раза в 3 секунды
    на человека» у /друзья-онлайн, когда один и тот же человек (в этом
    файле — Зоя) стучится в неё несколько раз подряд по делу, а не для
    проверки самого предела. */
function ждать(мс) {
  return new Promise(function (готово) { setTimeout(готово, мс); });
}

