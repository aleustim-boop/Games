const журнал = [];

function поддельныйTelegram(метод, тело) {
  журнал.push({ метод: метод, тело: тело });
  if (метод === 'getMe') return { ok: true, result: { id: 777, is_bot: true, username: ИМЯ_БОТА } };
  if (метод === 'sendMessage') return { ok: true, result: { message_id: журнал.length } };
  return { ok: false, error_code: 400, description: 'Bad Request' };
}

/** Все письма, ушедшие этому человеку. */
function письмаКому(номер) {
  return журнал.filter(function (запись) {
    return запись.метод === 'sendMessage' && Number(запись.тело.chat_id) === номер;
  });
}

/** Сколько всего писем ушло за весь прогон. */
function всегоПисем() {
  return журнал.filter(function (запись) { return запись.метод === 'sendMessage'; }).length;
}

/* ---------------------------------------------------------------------
   Подпись Telegram — по тому же правилу, что у сервера.
   --------------------------------------------------------------------- */

function подписать(поля) {
  const строки = Object.keys(поля)
    .filter(function (к) { return к !== 'hash'; })
    .map(function (к) { return к + '=' + поля[к]; })
    .sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(ТОКЕН_ДЛЯ_ПРОБЫ).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}

/** initData так, как её присылает настоящая страница Telegram. */
function подписьИгрока(номер, имя) {
  const поля = {
    query_id: 'AAF' + номер,
    user: JSON.stringify({ id: номер, first_name: имя, username: 'igrok' + номер }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  const сподписью = Object.assign({}, поля, { hash: подписать(поля) });
  return Object.keys(сподписью)
    .map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(сподписью[к]); })
    .join('&');
}

