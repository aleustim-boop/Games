/* ---------------------------------------------------------------------
   Утечка номеров Telegram по ВСЕМ собранным телам разом — тот же
   приём, что в tests/друзья-онлайн-сервер.js: ключи (32-значные hex-
   слова) вычищаем перед поиском длинных цифровых цепочек, иначе
   случайные байты ключа время от времени сами складываются в число.
   --------------------------------------------------------------------- */

function собратьКлючи(тексты) {
  const найдено = new Set();
  const рег = /\b[0-9a-f]{32}\b/g;
  for (const текст of тексты) {
    let м;
    while ((м = рег.exec(текст))) найдено.add(м[0]);
  }
  return Array.from(найдено);
}

function проверитьУтечки() {
  console.log('7. Ни в одном собранном ответе нет числа, похожего на номер Telegram');
  const ключи = собратьКлючи(собранныеТела);
  let утечек = 0;
  собранныеТела.forEach(function (текст, к) {
    let очищенный = текст;
    for (const ключ of ключи) очищенный = очищенный.split(ключ).join('<ключ>');
    if (/\d{6,}/.test(очищенный)) {
      утечек++;
      console.log('  подробности утечки в ответе №' + к + ': ' + очищенный.slice(0, 300));
    }
  });
  проверить(утечек === 0,
    'длинные числа (похожие на номер Telegram) не встречаются ни в одном из ' + собранныеТела.length +
    ' собранных ответов, а нашлись в ' + утечек);
}

