'use strict';

/* =====================================================================
   ИТОГ В ЧАТ: проверка модуля server/итог-в-чат.js (этап Э3 плана
   штаб/план-бот-группы.md). Модуль чистый: сети и Telegram нет — вместо
   них поддельные отправить/имяПоНомеру и управляемые часы.

   Запуск:
       node tests/итог-в-чат.js

   Ломающий прогон (обязан покраснеть):
       node tests/итог-в-чат.js --модуль <путь к копии модуля>
   Копию с порчей кладут во временную папку вместе с копией названия.js.
   Файл проекта не портится. Порчи: порог 3 минут → 0; 403 не забывает
   чат; 429 повторяет без ограничения; в текст попадает имя из игры;
   старый текст с родом («Саша обыграл Петю») — краснеет сверка «без рода».

   Ноль найденного — провал: каждая сверка «сообщение ушло» требует точного
   числа больше нуля, а не «если нашлось».

   Выход 0 — провалов нет, 1 — есть.
   ===================================================================== */

const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const индексМодуля = process.argv.indexOf('--модуль');
const ПУТЬ_МОДУЛЯ = индексМодуля !== -1 && process.argv[индексМодуля + 1]
  ? path.resolve(process.argv[индексМодуля + 1])
  : path.join(КОРЕНЬ, 'server', 'итог-в-чат.js');
const итог = require(ПУТЬ_МОДУЛЯ);

let провалов = 0;
let сверок = 0;
function вывести(строка) { process.stdout.write(строка + '\n'); }
function проверить(что, условие, подробность) {
  сверок++;
  if (условие) { вывести('  ок    ' + что); return; }
  провалов++;
  вывести('  ПРОВАЛ ' + что + (подробность !== undefined ? '  → ' + подробность : ''));
}

const ЧАТ = -100123;
const МИНУТА = 60 * 1000;
const ИМЕНА = { 1: 'Саша', 2: 'Петя', 3: 'Лена', 4: 'Вася', 5: 'Андрей', 6: 'Ольга' };
const всеТексты = [];   // всё, что модуль отправил за прогон: сверка «без рода»

/** Поддельный мир: часы, отправки, отложенные дела; ответ задаёт проверка. */
function стенд(ответ) {
  const мир = { время: 1000000, отправки: [], задачи: [], ответ: ответ || function () { return { ok: true }; } };
  итог.забытьВсё();
  итог.подключить({
    отправить: function (тело) { мир.отправки.push(тело); всеТексты.push(String(тело.text)); return мир.ответ(тело, мир.отправки.length); },
    имяПоНомеру: function (номер) { return ИМЕНА[номер] || ''; },
    сейчас: function () { return мир.время; },
    отложить: function (дело, мс) { мир.задачи.push({ дело: дело, мс: мс }); }
  });
  return мир;
}
function ждать() { return new Promise(function (готово) { setImmediate(готово); }); }

function человек(номер, исход, лишнее) {
  return Object.assign({ номер: номер, этоБот: false, имя: 'Набрано' + номер, исход: исход, место: номер, напарник: null }, лишнее || {});
}
function бот(исход, место) { return { номер: 0, этоБот: true, имя: 'Бот', исход: исход, место: место, напарник: null }; }
function итогПартии(игра, места, чат) { return { что: 'итог', чат: чат === undefined ? ЧАТ : чат, игра: игра, места: места }; }

/** Одно событие → список отправленных тел. */
async function отправленное(данные) {
  const мир = стенд();
  итог.событие(данные);
  await ждать();
  return мир.отправки;
}

async function главное() {
  вывести('Тексты');
  let о = await отправленное(итогПартии('шашки', [человек(1, 'победа'), человек(2, 'поражение')]));
  проверить('двое: «Сыграли в шашки: Саша — победа, Петя — поражение.»', о.length === 1 && о[0].text === 'Сыграли в шашки: Саша — победа, Петя — поражение.', JSON.stringify(о));
  проверить('в чат, а не кому-то ещё', о.length === 1 && о[0].chat_id === ЧАТ);
  проверить('кнопка «Реванш?» с stol:shashki', о.length === 1 && JSON.stringify(о[0].reply_markup) ===
    JSON.stringify({ inline_keyboard: [[{ text: 'Реванш?', callback_data: 'stol:shashki' }]] }), JSON.stringify(о[0] && о[0].reply_markup));

  о = await отправленное(итогПартии('шахматы', [человек(1, 'ничья'), человек(2, 'ничья')]));
  проверить('ничья: «Саша и Петя сыграли вничью в шахматы.»', о.length === 1 && о[0].text === 'Саша и Петя сыграли вничью в шахматы.', JSON.stringify(о));

  о = await отправленное(итогПартии('дурак', [человек(1, 'победа'), человек(2, 'поражение'), человек(3, 'победа')]));
  проверить('дурак: «В дураках: Петя. Вышли: Саша, Лена.»', о.length === 1 &&
    о[0].text === 'В дураках: Петя. Вышли: Саша, Лена.', JSON.stringify(о));

  о = await отправленное(итогПартии('дурак', [человек(1, 'победа'), человек(2, 'поражение'), человек(4, 'поражение')]));
  проверить('дурак, несколько в дураках: «В дураках: Петя, Вася. Вышли: Саша.»', о.length === 1 &&
    о[0].text === 'В дураках: Петя, Вася. Вышли: Саша.', JSON.stringify(о));

  о = await отправленное(итогПартии('деберц', [
    человек(1, 'победа', { место: 1, напарник: 3 }), человек(2, 'поражение', { место: 2, напарник: 4 }),
    человек(3, 'победа', { место: 3, напарник: 1 }), человек(4, 'поражение', { место: 4, напарник: 2 })]));
  проверить('парами: «Сыграли в деберц: Саша и Лена — победа, Петя и Вася — поражение.»', о.length === 1 &&
    о[0].text === 'Сыграли в деберц: Саша и Лена — победа, Петя и Вася — поражение.', JSON.stringify(о));

  о = await отправленное(итогПартии('покер', [человек(1, 'победа'), человек(2, 'поражение'), человек(3, 'поражение')]));
  проверить('больше двух без пар: «Победа: Саша. За столом: Петя, Лена.»', о.length === 1 &&
    о[0].text === 'Победа: Саша. За столом: Петя, Лена.', JSON.stringify(о));

  о = await отправленное(итогПартии('покер', [человек(1, 'победа'), человек(2, 'поражение'), человек(3, 'победа')]));
  проверить('несколько победителей: «Победа: Саша, Лена. За столом: Петя.»', о.length === 1 &&
    о[0].text === 'Победа: Саша, Лена. За столом: Петя.', JSON.stringify(о));

  о = await отправленное(итогПартии('шашки', [человек(1, 'внеСчёта'), человек(2, 'внеСчёта')]));
  проверить('вне счёта: «закончили по согласию»', о.length === 1 && о[0].text.indexOf('закончили по согласию') !== -1, JSON.stringify(о));

  о = await отправленное(итогПартии('шашки', [человек(5, 'победа'), человек(6, 'поражение')]));
  проверить('имена не склоняются: «Сыграли в шашки: Андрей — победа, Ольга — поражение.»', о.length === 1 &&
    о[0].text === 'Сыграли в шашки: Андрей — победа, Ольга — поражение.', JSON.stringify(о));

  о = await отправленное(итогПартии('шашки', [человек(1, 'победа'), человек(999, 'поражение')]));
  проверить('неизвестный человек — «игрок»', о.length === 1 && о[0].text === 'Сыграли в шашки: Саша — победа, игрок — поражение.', JSON.stringify(о));

  о = await отправленное(итогПартии('шашки', [человек(1, 'поражение'), бот('победа', 2)]));
  проверить('с ботом, но один человек — не пишем', о.length === 0, JSON.stringify(о));

  о = await отправленное(итогПартии('покер', [человек(1, 'победа'), человек(2, 'поражение'), бот('поражение', 3)]));
  проверить('бот в списке — «бот»', о.length === 1 && о[0].text === 'Победа: Саша. За столом: Петя, бот.', JSON.stringify(о));

  вывести('Имя из игры в текст не попадает');
  о = await отправленное(итогПартии('шашки', [человек(1, 'победа', { имя: 'ХАКЕР<b>СЛОВО' }), человек(2, 'поражение', { имя: 'ЧУЖОЕИМЯ' })]));
  проверить('нашли сообщение и в нём нет имён из игры', о.length === 1 && о[0].text.indexOf('ХАКЕР') === -1 &&
    о[0].text.indexOf('ЧУЖОЕИМЯ') === -1 && о[0].text.indexOf('Набрано') === -1 && о[0].text === 'Сыграли в шашки: Саша — победа, Петя — поражение.', JSON.stringify(о));

  вывести('Тексты без рода и падежей');
  const сРодом = ['обыграл', 'остался', 'остались', 'Победил'];
  const всеТекстыДоСих = всеТексты.slice();
  проверить('опора — текстов собрано не меньше десяти (' + всеТекстыДоСих.length + ')', всеТекстыДоСих.length >= 10);
  const сСловомРода = всеТекстыДоСих.filter(function (т) {
    return сРодом.some(function (слово) { return т.indexOf(слово) !== -1; });
  });
  проверить('ни в одном тексте нет «' + сРодом.join('», «') + '»', сСловомРода.length === 0, JSON.stringify(сСловомРода));

  вывести('Когда не пишем');
  const два = [человек(1, 'победа'), человек(2, 'поражение')];
  о = await отправленное(итогПартии('шашки', два, null));
  проверить('нет чата', о.length === 0);
  о = await отправленное(итогПартии('шашки', два, 777));
  проверить('чат ≥ 0 (личка) — не пишем', о.length === 0);
  о = await отправленное(итогПартии('шашки', два, 0));
  проверить('чат 0 — не пишем', о.length === 0);
  о = await отправленное(итогПартии('шашки', [человек(1, 'победа'), человек(1, 'поражение')]));
  проверить('один человек с двух устройств — не пишем', о.length === 0);
  о = await отправленное(итогПартии('шашки', [человек(1, 'победа')]));
  проверить('меньше двух людей — не пишем', о.length === 0);
  о = await отправленное({ что: 'другое', чат: ЧАТ, игра: 'шашки', места: два });
  проверить('чужое событие — не пишем', о.length === 0);

  вывести('Порог частоты: не чаще одного итога в 3 минуты на чат');
  let мир = стенд();
  итог.событие(итогПартии('шашки', два));
  мир.время += 2 * МИНУТА;
  итог.событие(итогПартии('шашки', два));
  await ждать();
  проверить('второй итог через 2 минуты — молчим (ушло ровно 1)', мир.отправки.length === 1, мир.отправки.length);
  итог.событие(итогПартии('шашки', два, -100999));
  await ждать();
  проверить('другой чат порог не задевает (ушло 2)', мир.отправки.length === 2 && мир.отправки[1].chat_id === -100999, мир.отправки.length);
  мир.время += 2 * МИНУТА;
  итог.событие(итогПартии('шашки', два));
  await ждать();
  проверить('через 4 минуты после первого — пишем (ушло 3)', мир.отправки.length === 3, мир.отправки.length);

  вывести('403 и «chat not found» — чат забываем');
  мир = стенд(function () { return { ok: false, error_code: 403, description: 'Forbidden: bot was kicked from the group chat' }; });
  итог.событие(итогПартии('шашки', два));
  await ждать();
  мир.время += 10 * МИНУТА;
  итог.событие(итогПартии('шашки', два));
  await ждать();
  проверить('после 403 больше в этот чат не пишем (всего 1 попытка)', мир.отправки.length === 1, мир.отправки.length);
  итог.событие(итогПартии('шашки', два, -100555));
  await ждать();
  проверить('другой чат после этого пишется', мир.отправки.length === 2 && мир.отправки[1].chat_id === -100555, мир.отправки.length);

  мир = стенд(function () { return { ok: false, error_code: 400, description: 'Bad Request: chat not found' }; });
  итог.событие(итогПартии('шашки', два));
  await ждать();
  мир.время += 10 * МИНУТА;
  итог.событие(итогПартии('шашки', два));
  await ждать();
  проверить('«chat not found» — тоже забываем (всего 1 попытка)', мир.отправки.length === 1, мир.отправки.length);

  вывести('429 — ровно один повтор');
  мир = стенд(function () { return { ok: false, error_code: 429, parameters: { retry_after: 5 } }; });
  итог.событие(итогПартии('шашки', два));
  await ждать();
  проверить('после 429 повтор поставлен на 5 секунд', мир.задачи.length === 1 && мир.задачи[0].мс === 5000, JSON.stringify(мир.задачи.map(function (з) { return з.мс; })));
  мир.задачи.shift().дело();
  await ждать();
  проверить('повтор ушёл (всего 2 отправки)', мир.отправки.length === 2, мир.отправки.length);
  проверить('при втором 429 нового повтора нет', мир.задачи.length === 0, мир.задачи.length);
  проверить('повтор — то же сообщение', мир.отправки.length === 2 && мир.отправки[0].text === мир.отправки[1].text &&
    мир.отправки[1].chat_id === ЧАТ);

  вывести('migrate_to_chat_id — один повтор по новому номеру');
  const НОВЫЙ = -1001234567890;
  мир = стенд(function (тело) {
    return тело.chat_id === ЧАТ
      ? { ok: false, error_code: 400, description: 'Bad Request: group chat was upgraded to a supergroup chat', parameters: { migrate_to_chat_id: НОВЫЙ } }
      : { ok: true };
  });
  итог.событие(итогПартии('шашки', два));
  await ждать();
  проверить('повтор ушёл в новый чат (всего 2: старый, новый)', мир.отправки.length === 2 &&
    мир.отправки[0].chat_id === ЧАТ && мир.отправки[1].chat_id === НОВЫЙ, JSON.stringify(мир.отправки.map(function (т) { return т.chat_id; })));
  мир.время += 10 * МИНУТА;
  итог.событие(итогПартии('шашки', два));
  await ждать();
  проверить('следующий итог по старому номеру сразу идёт в новый (3-я отправка)', мир.отправки.length === 3 &&
    мир.отправки[2].chat_id === НОВЫЙ, JSON.stringify(мир.отправки.map(function (т) { return т.chat_id; })));

  мир = стенд(function () { return { ok: false, error_code: 400, parameters: { migrate_to_chat_id: НОВЫЙ } }; });
  итог.событие(итогПартии('шашки', два));
  await ждать();
  проверить('переезд повторяется только один раз (всего 2 отправки)', мир.отправки.length === 2, мир.отправки.length);

  вывести('Выключен без отправить');
  итог.забытьВсё();
  итог.подключить({});
  итог.событие(итогПартии('шашки', два));
  проверить('без отправить — тихо, без падения', true);

  вывести('Итого проверок: ' + сверок + ', провалов: ' + провалов);
  process.exit(провалов === 0 ? 0 : 1);
}

главное().catch(function (беда) {
  вывести('Проверка упала: ' + (беда && беда.stack ? беда.stack : беда));
  process.exit(1);
});
