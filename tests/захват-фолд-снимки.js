const ТИПЫ = {
  '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'application/javascript; charset=utf-8',
  '.json': 'application/json', '.svg': 'image/svg+xml', '.webp': 'image/webp', '.png': 'image/png', '.jpg': 'image/jpeg',
  '.woff2': 'font/woff2', '.woff': 'font/woff', '.ttf': 'font/ttf'
};

// Порча css «на лету»: отдаём испорченную КОПИЮ текста, файл проекта остаётся как есть.
function испортитьCss(текст) {
  if (режимПорчи === 'признак') return текст.replace(/(@media[^{]*min-aspect-ratio:\s*10\/13[^{]*\{[\s\S]*?--захват-капсулы-сбоку:\s*)1/, '$10');
  if (режимПорчи === 'пульт') return текст.replace(/(@media[^{]*min-aspect-ratio:\s*10\/13[^{]*\{[\s\S]*?--захват-пульт-наибольший:\s*)188px/, '$160px');
  return текст;
}

function поднятьСервер() {
  const с = http.createServer((запрос, ответ) => {
    let п = '/';
    try { п = decodeURIComponent(запрос.url.split('?')[0]); } catch (_) { /* как есть */ }
    const файл = path.join(КОРЕНЬ, п === '/' ? 'index.html' : п);
    if (!path.relative(КОРЕНЬ, файл).startsWith('..') && fs.existsSync(файл) && fs.statSync(файл).isFile()) {
      let тело = fs.readFileSync(файл);
      if (ломаем && /style-захват\.css$/.test(файл)) {
        const исходный = тело.toString('utf8');
        const порченый = испортитьCss(исходный);
        // порча обязана что-то изменить, иначе ломающий запуск ничего не доказывает
        if (режимПорчи !== 'адрес') проверить('порча css нашла место (режим «' + режимПорчи + '»)', порченый !== исходный);
        тело = Buffer.from(порченый, 'utf8');
      }
      ответ.writeHead(200, { 'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'application/octet-stream' });
      ответ.end(тело);
    } else { ответ.writeHead(404); ответ.end('нет такого файла'); }
  });
  return new Promise((г) => с.listen(0, '127.0.0.1', () => г(с)));
}

// Замер в странице: всё в CSS px от левого верха окна.
function замер() {
  const р = (у) => { if (!у) return null; const б = у.getBoundingClientRect(); return { x: Math.round(б.left), y: Math.round(б.top), ш: Math.round(б.width), в: Math.round(б.height), н: Math.round(б.bottom), п: Math.round(б.right) }; };
  const $ = (и) => document.getElementById(и);
  const видим = (у) => { const б = у.getBoundingClientRect(); return б.width > 0 && б.height > 0 && getComputedStyle(у).visibility !== 'hidden'; };
  const узелКарты = $('захват-карта');
  const окно = window.ЗахватСтол ? window.ЗахватСтол.замеритьОкно(document) : null;
  const экран = $('экран-игры');
  const сте = экран ? getComputedStyle(экран) : null;
  const видимые = Array.from(document.querySelectorAll('#захват-игроки .захват-игрок')).filter((у) => !у.classList.contains('скрыт') && видим(у));
  const шайбы = Array.from(document.querySelectorAll('.захват-шайба')).filter(видим).map((у) => у.getBoundingClientRect());
  const подписи = Array.from(document.querySelectorAll('.захват-пилюля')).filter(видим).map((у) => у.getBoundingClientRect());
  let земля = null;
  if (шайбы.length) {
    const л = Math.min.apply(null, шайбы.map((б) => б.left)), п = Math.max.apply(null, шайбы.map((б) => б.right));
    const в = Math.min.apply(null, шайбы.map((б) => б.top)), н = Math.max.apply(null, шайбы.map((б) => б.bottom));
    земля = { x: Math.round(л), y: Math.round(в), ш: Math.round(п - л), в: Math.round(н - в) };
  }
  const кx = узелКарты ? parseFloat(узелКарты.style.getPropertyValue('--карта-x')) : NaN;
  const кy = узелКарты ? parseFloat(узелКарты.style.getPropertyValue('--карта-y')) : NaN;
  const бУзла = узелКарты ? узелКарты.getBoundingClientRect() : null;
  // Карта стоит по центру полосы окна [лево, право]: ширина = ширина полосы − 2 × (x − лево). Без боковых краёв (телефон) лево 0, право = ширина узла.
  const местоШирина = бУзла && окно ? Math.round(((окно.право - окно.лево) - 2 * (кx - окно.лево)) * 10) / 10 : null;
  const пультЭл = $('захват-пульт');
  const верхняя = document.querySelector('#экран-игры > .верх-игры');
  const раундЭл = $('захват-раунд');
  const внизСодержимого = экран ? экран.getBoundingClientRect().bottom - (parseFloat(сте.borderBottomWidth) || 0) - (parseFloat(сте.paddingBottom) || 0) : null;
  const наибольший = сте ? parseFloat(сте.getPropertyValue('--захват-пульт-наибольший')) : NaN;
  const рамка = (б) => ({ x: б.left, y: б.top, п: б.right, н: б.bottom });
  return {
    окно: window.innerWidth + '×' + window.innerHeight,
    телеграм: document.documentElement.classList.contains('в-телеграме'),
    признакСбоку: getComputedStyle(document.body).getPropertyValue('--захват-капсулы-сбоку').trim(),
    узелКарты: р(узелКарты), холст: р($('захват-холст')),
    окноКартыВУзле: окно ? { верх: Math.round(окно.верх), низ: Math.round(окно.низ), лево: Math.round(окно.лево), право: Math.round(окно.право) } : null,
    местоКарты: { x: кx, y: кy, ширина: местоШирина },
    левоПравоОкна: окно && бУзла ? { л: Math.round(бУзла.left + окно.лево), п: Math.round(бУзла.left + окно.право) } : null,
    землеШайбыПоЦентрам: земля,
    плашки: видимые.map(р),
    пульт: пультЭл && видим(пультЭл) ? р(пультЭл) : null,
    верхПультаНаибольшего: внизСодержимого !== null && isFinite(наибольший) ? Math.round(внизСодержимого - наибольший) : null,
    верхняяСтрока: верхняя && видим(верхняя) ? р(верхняя) : null,
    таблички: шайбы.map(рамка), подписи: подписи.map(рамка),
    подсказка: ($('захват-подсказка') || {}).textContent, раунд: (раундЭл || {}).textContent,
    детиКарты: узелКарты ? Array.from(узелКарты.querySelectorAll('*')).slice(0, 12).map((у) => { const б = у.getBoundingClientRect(); return у.tagName + '#' + у.id + '.' + String(у.className).slice(0, 30) + ' ' + Math.round(б.left) + ',' + Math.round(б.top) + ' ' + Math.round(б.width) + '×' + Math.round(б.height); }) : []
  };
}

