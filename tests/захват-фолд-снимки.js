// Настройки: «До победы» и ряды пилюль не вылезают за панель (на 320 это было слабое место).
function замерНастроек() {
  const р = (б) => ({ л: Math.round(б.left), п: Math.round(б.right), в: Math.round(б.top), н: Math.round(б.bottom) });
  const панель = document.querySelector('#захват-настройки .захват-панель');
  const победа = document.querySelector('#захват-выбор-раунды button[data-значение="победа"]');
  const ряд = document.getElementById('захват-выбор-раунды');
  const ряды = Array.from(document.querySelectorAll('#захват-настройки .захват-выбор-числа'));
  const бП = панель && панель.getBoundingClientRect();
  const сП = панель && getComputedStyle(панель);
  const внутриПанели = бП ? бП.right - (parseFloat(сП.paddingRight) || 0) : null;
  return {
    экран: window.innerWidth,
    панель: бП ? р(бП) : null,
    панельКласс: панель ? panel_classes(панель) : null,
    победа: победа ? р(победа.getBoundingClientRect()) : null,
    победаТекст: победа ? победа.textContent.trim() : null,
    вылезаетПилюля: ряды.some((я) => Array.from(я.children).some((к) => внутриПанели !== null && к.getBoundingClientRect().right > внутриПанели + 0.5)),
    вылезаетРяд: ряды.some((я) => я.scrollWidth > я.clientWidth + 1),
    рядРаундов: ряд ? р(ряд.getBoundingClientRect()) : null,
    стеклоПанели: panel_glass(панель)
  };
  function panel_classes(у) { return у.className; }
  function panel_glass(у) { return у ? (getComputedStyle(у).backdropFilter || getComputedStyle(у).webkitBackdropFilter || '') : null; }
}

async function лобби(браузер, порт, окно, ошибки) {
  const { контекст, страница } = await открыть(браузер, порт, окно, ошибки, true);
  const ш = окно.метка;
  try {
    const л = await страница.evaluate(() => { const у = document.getElementById('экран-лобби'); const б = у && у.getBoundingClientRect(); return у ? { виден: у.classList.contains('экран--виден'), ш: Math.round(б.width), в: Math.round(б.height), прокрутка: у.scrollHeight + '/' + у.clientHeight } : null; });
    проверить('лобби ' + ш + ': экран найден и виден (ноль — провал)', !!л && л.виден);
    console.log('  [Лобби ' + ш + '] ' + JSON.stringify(л));
    await снять(страница, '01', 'лобби', ш);
    await страница.click('#захват-боты', { timeout: 5000 });
    await страница.waitForTimeout(700);
    const нас = await страница.evaluate(() => { const у = document.getElementById('захват-настройки'); const к = у && у.querySelector('.захват-панель'); const б = к && к.getBoundingClientRect();
      return { виден: !!у && у.classList.contains('экран--виден'), панель: б ? Math.round(б.width) + '×' + Math.round(б.height) : null, подпись: (document.getElementById('захват-подпись-карты') || {}).textContent,
        параметры: Array.from(у.querySelectorAll('.захват-выбор-параметра > strong')).map((x) => x.textContent) }; });
    проверить('настройки ' + ш + ': экран найден и виден (ноль — провал)', нас.виден);
    проверить('настройки ' + ш + ': шаги настроек найдены (ноль — провал)', нас.параметры.length > 0);
    console.log('  [Настройки ' + ш + '] ' + JSON.stringify(нас));
    const м = await страница.evaluate(замерНастроек);
    console.log('      «До победы»: ' + JSON.stringify(м.победа) + ' «' + м.победаТекст + '» | панель ' + JSON.stringify(м.панель) + ' | класс панели «' + м.панельКласс + '» | blur ' + м.стеклоПанели);
    проверить('настройки ' + ш + ': кнопка «До победы» найдена (ноль — провал)', !!м.победа && м.победаТекст.length > 0);
    проверить('настройки ' + ш + ': «До победы» целиком на экране и в панели',
      !!м.победа && !!м.панель && м.победа.л >= м.панель.л && м.победа.п <= м.панель.п && м.победа.п <= м.экран, JSON.stringify([м.победа, м.панель, м.экран]));
    проверить('настройки ' + ш + ': ни одна пилюля и ни один ряд не вылезают за панель', !м.вылезаетПилюля && !м.вылезаетРяд, 'пилюля ' + м.вылезаетПилюля + ', ряд ' + м.вылезаетРяд);
    проверить('настройки ' + ш + ': панель на стекле (класс стекло-панель)', /(^|\s)стекло-панель(\s|$)/.test(м.панельКласс || ''), м.панельКласс);
    await снять(страница, '02', 'настройки-4-игрока', ш);
    await страница.click('#захват-выбор-число button[data-значение="3"]');
    await страница.waitForTimeout(300);
    await снять(страница, '03', 'настройки-3-игрока', ш);
  } catch (е) {
    проверить('лобби ' + ш + ' не упало', false, String(е && е.stack || е).split('\n').slice(0, 3).join(' / '));
  }
  await контекст.close();
}

