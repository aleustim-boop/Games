function итогПроверки(имя, условие, пояснение) {
  проверок++;
  if (условие) { console.log('  ок      ' + имя); return; }
  провалов++;
  console.log('  ПРОВАЛ  ' + имя + (пояснение ? ' — ' + пояснение : ''));
}

/* Свой сервер файлов: деберц-экран.js и style-деберц.css подменяются копиями (для порчи). */
function поднятьСерверФайлов() {
  const подмены = { 'деберц-экран.js': ФАЙЛ_ЭКРАНА, 'style-деберц.css': ФАЙЛ_СТИЛЯ };
  const сервер = http.createServer((запрос, ответ) => {
    let путь;
    try { путь = decodeURIComponent(new URL(запрос.url, 'http://x').pathname); } catch (_) { ответ.writeHead(400); ответ.end(); return; }
    const файл = path.join(КОРЕНЬ, путь);
    if (path.relative(КОРЕНЬ, файл).startsWith('..')) { ответ.writeHead(403); ответ.end(); return; }
    fs.readFile(подмены[path.basename(файл)] || файл, (ош, данные) => {
      if (ош) { ответ.writeHead(404); ответ.end('нет файла'); return; }
      ответ.writeHead(200, { 'Content-Type': ТИПЫ_ФАЙЛОВ[path.extname(файл).toLowerCase()] || 'application/octet-stream', 'Cache-Control': 'no-store' });
      ответ.end(данные);
    });
  });
  return new Promise((готово, беда) => { сервер.once('error', беда); сервер.listen(0, '127.0.0.1', () => готово(сервер)); });
}

/* Вид стола «торговля, круг 1, мой ход» от настоящих правил и настоящего видДляИгрока (как приходит с сервера). */
function собратьВидТорговли(мест) {
  process.env.ДАННЫЕ_ИГРЫ = path.join(os.tmpdir(), 'деберц-выход-слова-данные-' + process.pid);
  const Д = require(path.join(КОРЕНЬ, 'server', 'игры', 'деберц.js'));
  const ПРАВИЛА = require(path.join(КОРЕНЬ, 'js', 'game.js'));
  const имена = ['Вы', 'Александра', 'Константин', 'Святослав'];
  const ключи = ПРАВИЛА.создатьПартию({ игроков: ПРАВИЛА.МАКС_ИГРОКОВ }).игроки.slice(0, мест);
  const п = Д.раздать(null, { игроки: ключи });
  const места = п.игроки.map((ключ, i) => ({ ключ, имя: имена[i], этоБот: false, хозяин: i === 0, наСвязи: true, ушёл: false, хочетЕщё: false }));
  const вид = Д.видДляИгрока(п, п.игроки[0], { код: 'ТЕСТ', этап: 'партия', версия: 1, номерСобытия: 1, события: '', места, мест, мойНомер: 0,
    яХозяин: true, можноНачать: false, парами: false, соперникПришёл: true, соперникНаСвязи: true, имяСоперника: имена[1] });
  вид.деберц.ход = 0;
  return вид;
}

/* В СТРАНИЦЕ: слова подписи круга и прямоугольники всех карт руки — по ним ищем перекрытие. */
function замерПодписиКруга() {
  const подпись = document.getElementById('деберц-статус');
  const р = у => { const к = у.getBoundingClientRect(); return { x: к.left, y: к.top, r: к.right, b: к.bottom }; };
  const диапазон = document.createRange();
  if (подпись) диапазон.selectNodeContents(подпись);
  return {
    текст: подпись ? подпись.textContent.trim() : '',
    слова: подпись ? р(диапазон) : null,
    карты: Array.from(document.querySelectorAll('#карты-человека .карта')).map(р)
  };
}

/* вТелеграме: true — поддельный Telegram (там «‹» экрана спрятана, остаётся системная стрелка);
   false — обычный браузер без Telegram (там видна «‹» экрана). */
async function открытьСтраницу(браузер, адрес, робот, ошибки, вТелеграме) {
  const контекст = await браузер.newContext({ viewport: ЭКРАН_390, reducedMotion: 'reduce' });
  const страница = await контекст.newPage();
  страница.on('pageerror', о => ошибки.push('исключение: ' + о.message));
  if (вТелеграме) await робот.подготовитьПодделку(страница, {}); else await робот.безTelegram(страница);
  await страница.goto(адрес + 'деберц.html?сервер=' + encodeURIComponent('http://127.0.0.1:1'));
  await страница.waitForFunction(() => window.ИграПоСети && window.ЛистЕщё, null, { timeout: 8000 });
  await страница.waitForTimeout(300);
  return { контекст, страница };
}

/* Сетевая партия: показать стол так же, как это делает ответ сервера. */
async function сестьЗаСетевойСтол(страница, вид) {
  await страница.evaluate(в => window.ИграПоСети.показатьВид(в), вид);
  await страница.waitForTimeout(500);
}

/* Партия с ботами (без сети): лобби → настройки → «Начать». */
async function сестьЗаСтолСБотом(страница) {
  await страница.locator('#деберц-боты').click({ timeout: 4000 });
  await страница.locator('#деберц-начать').click({ timeout: 4000 });
  await страница.waitForTimeout(400);
}

async function состояние(страница) {
  return страница.evaluate(() => ({
    столВиден: document.getElementById('экран-игры').classList.contains('экран--виден'),
    плашкаОткрыта: document.getElementById('деберц-выход').open === true,
    плашкаСлова: document.getElementById('деберц-выход-заголовок').textContent,
    стрелкаЕсть: Boolean(window.ПоддельныйТелеграм && typeof window.ПоддельныйТелеграм.нажатьНазад === 'function'),
    путь: location.pathname
  }));
}

/* Нажать «‹» (кнопка экрана) или стрелку «Назад» (система Telegram). */
async function нажатьВыход(страница, чем) {
  if (чем === 'кнопка') {
    const узел = страница.locator('#деберц-назад');
    if (await узел.count() !== 1) return false;
    await узел.click({ timeout: 4000 });
    return true;
  }
  return страница.evaluate(() => {
    if (!window.ПоддельныйТелеграм || typeof window.ПоддельныйТелеграм.нажатьНазад !== 'function') return false;
    window.ПоддельныйТелеграм.нажатьНазад();
    return true;
  });
}

async function случайВыхода(браузер, адрес, робот, ошибки, чем, вПартии) {
  const метка = '[' + (чем === 'кнопка' ? '«‹»' : '«Назад»') + (вПартии ? ' в партии' : ' вне партии') + '] ';
  const { контекст, страница } = await открытьСтраницу(браузер, адрес, робот, ошибки, чем === 'стрелка');
  try {
    if (вПартии) await сестьЗаСетевойСтол(страница, собратьВидТорговли(3)); else await сестьЗаСтолСБотом(страница);
    const до = await состояние(страница);
    итогПроверки(метка + 'стол на экране, окно выхода закрыто', до.столВиден && !до.плашкаОткрыта,
      'стол виден: ' + до.столВиден + ', окно открыто: ' + до.плашкаОткрыта);
    if (чем === 'стрелка') итогПроверки(метка + 'стрелка Telegram найдена в странице', до.стрелкаЕсть, 'нет window.ПоддельныйТелеграм.нажатьНазад');
    const нажали = await нажатьВыход(страница, чем);
    итогПроверки(метка + 'выход нажат (' + (чем === 'кнопка' ? '#деберц-назад найден' : 'стрелка нажата') + ')', нажали, 'нажимать нечего');
    const ушли = await страница.waitForURL(/index\.html/, { timeout: вПартии ? 1500 : 4000 }).then(() => true).catch(() => false);
    if (вПартии) {
      const после = ушли ? null : await состояние(страница);
      итогПроверки(метка + 'открылась плашка «Выйти из партии?», со страницы не ушли',
        !ушли && после.плашкаОткрыта && после.плашкаСлова === 'Выйти из партии?',
        ушли ? 'ушли на index.html без вопроса' : 'окно открыто: ' + после.плашкаОткрыта + ', заголовок: «' + после.плашкаСлова + '»');
    } else {
      итогПроверки(метка + 'ушли к выбору игр (index.html) без плашки', ушли, 'остались на деберце');
    }
  } finally {
    await контекст.close();
  }
}

async function случайПодписи(браузер, адрес, робот, ошибки, снимок) {
  const метка = '[подпись круга] ';
  const { контекст, страница } = await открытьСтраницу(браузер, адрес, робот, ошибки, true);
  try {
    await сестьЗаСетевойСтол(страница, собратьВидТорговли(3));
    await страница.waitForTimeout(1500);   // раздача карт и раскладка веера
    const м = await страница.evaluate(замерПодписиКруга);
    итогПроверки(метка + 'подпись найдена и это «Круг 1. Принять открытую масть…»', /^Круг 1\. Принять открытую масть/.test(м.текст) && м.слова && м.слова.r > м.слова.x,
      'текст: «' + м.текст + '»');
    итогПроверки(метка + 'карты руки найдены (нужна хотя бы одна)', м.карты.length > 0, 'карт: ' + м.карты.length);
    const пересекается = м.слова ? м.карты.filter(к => м.слова.x < к.r - 0.5 && к.x < м.слова.r - 0.5 && м.слова.y < к.b - 0.5 && к.y < м.слова.b - 0.5) : [];
    итогПроверки(метка + 'ни одна карта веера не заходит на слова подписи (по прямоугольникам, 390×844)', пересекается.length === 0,
      'слова ' + JSON.stringify(м.слова) + ', пересекают карт: ' + пересекается.length);
    const самаяВысокая = м.карты.length ? Math.min(...м.карты.map(к => к.y)) : null;
    итогПроверки(метка + 'веер целиком ниже подписи (верх самой высокой карты ≥ низ слов)', м.слова && самаяВысокая !== null && самаяВысокая >= м.слова.b - 0.5,
      'верх карт: ' + самаяВысокая + ', низ слов: ' + (м.слова && м.слова.b));
    if (снимок) {
      fs.mkdirSync(path.dirname(ИМЯ_СНИМКА), { recursive: true });
      await страница.screenshot({ path: ИМЯ_СНИМКА });
      console.log('  снимок: ' + ИМЯ_СНИМКА);
    }
  } finally {
    await контекст.close();
  }
}

async function браузерныйСтенд(снимок) {
  const робот = require('./браузер-робот.js');
  const chromium = робот.chromium;
  const сервер = await поднятьСерверФайлов();
  const адрес = 'http://127.0.0.1:' + сервер.address().port + '/';
  console.log('Браузерная часть: ' + адрес + (ЗАПУСК_НА_КОПИИ ? '  (на копиях: ' + ФАЙЛ_ЭКРАНА + ', ' + ФАЙЛ_СТИЛЯ + ')' : ''));
  const браузер = await chromium.launch();
  const ошибки = [];
  try {
    for (const чем of ['кнопка', 'стрелка']) {
      await случайВыхода(браузер, адрес, робот, ошибки, чем, true);
      await случайВыхода(браузер, адрес, робот, ошибки, чем, false);
    }
    await случайПодписи(браузер, адрес, робот, ошибки, снимок);
    итогПроверки('консоль: исключений на странице нет', ошибки.length === 0, ошибки.slice(0, 2).join('; '));
  } finally {
    await браузер.close();
    сервер.close();
    fs.rmSync(path.join(os.tmpdir(), 'деберц-выход-слова-данные-' + process.pid), { recursive: true, force: true });
  }
  console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);
  if (проверок < МИНИМУМ_БРАУЗЕРНЫХ) { console.log('Проверок меньше ' + МИНИМУМ_БРАУЗЕРНЫХ + ' — часть выпала, это провал.'); return 1; }
  return провалов > 0 ? 1 : 0;
}

