function ломатьБраузерную(папка) {
  fs.mkdirSync(папка, { recursive: true });
  console.log('Ломающие запуски браузерной части, копии в ' + папка);
  let покраснело = 0;
  ПОРЧИ_БРАУЗЕРА.forEach((порча, n) => {
    const оригинал = порча.файл === 'экран' ? ЭКРАН : path.join(КОРЕНЬ, 'style-деберц.css');
    const части = fs.readFileSync(оригинал, 'utf8').split(порча.было);
    if (части.length !== 2) { console.log('  НЕТ СТРОКИ ДЛЯ ПОРЧИ (' + (части.length - 1) + ' раз): ' + порча.что); process.exit(2); }
    const копия = path.join(папка, (порча.файл === 'экран' ? 'деберц-экран-' : 'style-деберц-') + (n + 1) + (порча.файл === 'экран' ? '.js' : '.css'));
    fs.writeFileSync(копия, части.join(порча.стало));
    const запуск = spawnSync(process.execPath, [__filename, порча.файл === 'экран' ? '--экран' : '--стиль', копия], { encoding: 'utf8', timeout: 240000 });
    const красные = (запуск.stdout || '').split('\n').filter(с => с.includes('ПРОВАЛ  '));
    const наМетке = красные.filter(с => с.includes(порча.метка));
    const красная = запуск.status === 1 && наМетке.length > 0;
    if (красная) покраснело++;
    console.log('  ' + (красная ? 'покраснела' : 'НЕ ПОКРАСНЕЛА (код ' + запуск.status + ')') + ' — ' + порча.что + ': провалов ' + красные.length + ', из них на «' + порча.метка + '» ' + наМетке.length + '  [' + копия + ']');
    if (!красная && запуск.stderr) console.log('    stderr: ' + запуск.stderr.slice(0, 300));
  });
  console.log('Поломок ' + ПОРЧИ_БРАУЗЕРА.length + ', покраснело ' + покраснело);
  return покраснело === ПОРЧИ_БРАУЗЕРА.length ? 0 : 1;
}

