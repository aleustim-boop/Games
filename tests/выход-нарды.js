// Проверка тестировщика: дверь «завершить» на столе нард (js/нарды-экран.js),
// штаб/план-выход-из-партии.md, этап Э5.
//
// Запуск:
//   node tests/выход-нарды.js                  — обычный прогон, ждём 0 провалов
//   node tests/выход-нарды.js --файл <путь>    — тот же набор проверок, но код
//     js/нарды-экран.js берётся не с диска проекта, а из файла по указанному
//     пути (для ломающего запуска: путь ведёт на испорченную КОПИЮ во
//     временной папке, файл проекта эта проверка никогда не трогает).
//
// Как устроена проверка. js/нарды-экран.js — файл с настоящей доской: чтобы
// выполнить его целиком, пришлось бы подделывать десятки узлов разметки
// (24 пункта, бар, шашки, кубики…), и это проверяло бы построение доски,
// а не дверь «завершить». Вместо этого — тот же приём, что у
// tests/крестик-подтверждение.js: вырезаем тело нужной функции по СОБСТВЕННЫМ
// фигурным скобкам исходника (без второй, ручной копии логики внутри
// проверки) и выполняем его отдельно с поддельными «узел»/«режим»/«партия»/
// «видСети» и поддельными сдатьсяПоСети/уйтиВМеню — так проверяется
// настоящий, сегодняшний текст функций, а не пересказ их устройства.

'use strict';

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');

function аргумент(имя) {
  const индекс = process.argv.indexOf(имя);
  return индекс !== -1 ? process.argv[индекс + 1] : null;
}

const путьКФайлу = аргумент('--файл') || path.join(КОРЕНЬ, 'js', 'нарды-экран.js');

/* ---------- вырезание тела функции/объекта по фигурным скобкам ---------- */
/* Тот же приём, что в tests/крестик-подтверждение.js — своя копия внутри
   файла (общего помощника в проекте для этого нет), строки и комментарии
   пропускаются, чтобы «}» внутри них не сбивало счёт. */

class ПроваленаПроверка extends Error {}

function найтиПарнуюСкобку(текст, откудаОткрывающая) {
  let глубина = 0;
  for (let i = откудаОткрывающая; i < текст.length; i++) {
    const символ = текст[i];
    const два = текст.slice(i, i + 2);
    if (два === '//') {
      const конецСтроки = текст.indexOf('\n', i);
      i = конецСтроки === -1 ? текст.length : конецСтроки;
      continue;
    }
    if (два === '/*') {
      const конецБлока = текст.indexOf('*/', i + 2);
      i = конецБлока === -1 ? текст.length : конецБлока + 1;
      continue;
    }
    if (символ === "'" || символ === '"' || символ === '`') {
      const кавычка = символ;
      i++;
      while (i < текст.length && текст[i] !== кавычка) {
        if (текст[i] === '\\') i++;
        i++;
      }
      continue;
    }
    if (символ === '{') глубина++;
    else if (символ === '}') {
      глубина--;
      if (глубина === 0) return i;
    }
  }
  throw new ПроваленаПроверка('скобки не сошлись — файл повреждён сильнее, чем ожидалось');
}

/** Текст тела "function имя(...) { ... }" — со скобками. */
function телоФункции(текст, имяФункции) {
  const метка = 'function ' + имяФункции;
  const начало = текст.indexOf(метка);
  if (начало === -1) throw new ПроваленаПроверка('не нашёл "' + метка + '" в файле — функция пропала или переименована');
  const открывающая = текст.indexOf('{', начало);
  if (открывающая === -1) throw new ПроваленаПроверка('у "' + имяФункции + '" не нашёл открывающую скобку');
  const конец = найтиПарнуюСкобку(текст, открывающая);
  return текст.slice(открывающая, конец + 1);
}

/** Текст тела объектного литерала вида "начало = { ... }" (или "начало{ ... }"). */
function телоОбъекта(текст, началоВыражения) {
  const начало = текст.indexOf(началоВыражения);
  if (начало === -1) throw new ПроваленаПроверка('не нашёл "' + началоВыражения + '"');
  const открывающая = текст.indexOf('{', начало);
  if (открывающая === -1) throw new ПроваленаПроверка('после "' + началоВыражения + '" не нашёл "{"');
  const конец = найтиПарнуюСкобку(текст, открывающая);
  return текст.slice(открывающая, конец + 1);
}

/** Собрать вызываемую функцию из тела, вырезанного из НАСТОЯЩЕГО файла:
 *  свободные переменные тела («режим», «партия»…) становятся параметрами —
 *  так проверяется сегодняшний текст функции, а не его пересказ. */
function собратьФункцию(текст, имяФункции, параметры) {
  const тело = телоФункции(текст, имяФункции);
  const внутренности = тело.slice(1, -1);   // без внешних { }
  return new Function(параметры.join(', '), внутренности);
}

/* ---------- сами проверки ---------- */

function прогнатьПроверки(текст) {
  const строки = [];
  let ошибок = 0;
  function проверка(имя, дело) {
    try {
      const результат = дело();
      if (результат === false) throw new ПроваленаПроверка('условие не выполнено');
      строки.push('OK   ' + имя);
    } catch (ошибка) {
      ошибок++;
      строки.push('ПЛОХО ' + имя + ' — ' + ошибка.message);
    }
  }

  /* ---------- 1. Дверь «завершить» передана в ЛистЕщё.подключить({ двери: {...} }) ----------
     У нард (в отличие от шашек) подключение листа сделано не в отдельной
     функции «подключитьЛистЕщё», а прямо внутри «привязатьКнопки» — берём
     тело оттуда. */

  const телоПривязки = телоФункции(текст, 'привязатьКнопки');
  const телоДверей = телоОбъекта(телоПривязки, 'двери: {');
  const телоЗавершить = телоОбъекта(телоДверей, 'завершить: {');

  проверка('дверь «завершить» передана в ЛистЕщё.подключить({ двери: {...} })', function () {
    return телоЗавершить.length > 0;
  });

  /* «\b» кириллицу не понимает (штаб/уроки.md) — границу слова берём
     явно: следующий значимый символ после имени — запятая или «}». */
  проверка('«завершить».видна ссылается на партияИдётНаСтоле (не выдумана заново)', function () {
    return /видна\s*:\s*партияИдётНаСтоле\s*[,}]/.test(телоЗавершить);
  });

  проверка('«завершить».действие ссылается на завершитьПартиюИзЛиста', function () {
    return /действие\s*:\s*завершитьПартиюИзЛиста\s*[,}]/.test(телоЗавершить);
  });

  проверка('«завершить».текст ссылается на текстЗавершенияПартии', function () {
    return /текст\s*:\s*текстЗавершенияПартии\s*[,}]/.test(телоЗавершить);
  });

  проверка('старая дверь «вМеню» осталась без «видна» (совместимость вне партии)', function () {
    return /вМеню\s*:\s*\{\s*действие\s*:\s*уйтиВМеню\s*\}/.test(телоДверей);
  });

  проверка('сдатьсяПоСети по-прежнему шлёт на сервер действие «сдаться»', function () {
    const телоСдачи = телоФункции(текст, 'сдатьсяПоСети');
    return /действие\s*:\s*'сдаться'/.test(телоСдачи);
  });

  /* ---------- 1б. сдатьсяПоСети(): пока первая сдача летит на сервер, вторая не уходит ---------- */

  const сдатьсяПоСети = собратьФункцию(текст, 'сдатьсяПоСети', ['режим', 'видСети', 'ждёмОтветСети', 'отправитьВСеть']);

  проверка('сдатьсяПоСети: ждёмОтветСети=true — повторно ничего не отправляет', function () {
    let отправлено = false;
    сдатьсяПоСети('сеть', { завершена: false }, true, function () { отправлено = true; });
    return отправлено === false;
  });

  проверка('сдатьсяПоСети: ждёмОтветСети=false — отправляет, как раньше', function () {
    let отправлено = false;
    сдатьсяПоСети('сеть', { завершена: false }, false, function () { отправлено = true; });
    return отправлено === true;
  });

  /* ---------- 2. партияИдётНаСтоле(): видна() истинна в партии, ложна вне её ---------- */

  const партияИдётНаСтоле = собратьФункцию(текст, 'партияИдётНаСтоле', ['узел', 'режим', 'партия', 'видСети', 'ждёмОтветСети']);

  function узелСтола(виден) {
    return function (id) {
      if (id !== 'экран-игры') return null;
      return { classList: { contains: function (класс) { return класс === 'экран--виден' && виден; } } };
    };
  }

  проверка('партия с ботом идёт, стол виден: видна() = true', function () {
    return партияИдётНаСтоле(узелСтола(true), 'бот', { завершена: false }, null, false) === true;
  });

  проверка('партия с ботом ЗАВЕРШЕНА (итог поверх стола): видна() = false', function () {
    return партияИдётНаСтоле(узелСтола(true), 'бот', { завершена: true }, null, false) === false;
  });

  проверка('партии ещё нет (партия === null): видна() = false', function () {
    return партияИдётНаСтоле(узелСтола(true), 'бот', null, null, false) === false;
  });

  проверка('стол не виден (ушли в лобби), партия формально не завершена: видна() = false', function () {
    return партияИдётНаСтоле(узелСтола(false), 'бот', { завершена: false }, null, false) === false;
  });

  проверка('вдвоём на одном телефоне, стол виден: видна() = true', function () {
    return партияИдётНаСтоле(узелСтола(true), 'вдвоём', { завершена: false }, null, false) === true;
  });

  проверка('по сети партия идёт (видСети.завершена = false): видна() = true', function () {
    return партияИдётНаСтоле(узелСтола(true), 'сеть', null, { завершена: false }, false) === true;
  });

  проверка('по сети партия завершена: видна() = false', function () {
    return партияИдётНаСтоле(узелСтола(true), 'сеть', null, { завершена: true }, false) === false;
  });

  проверка('по сети видСети ещё не пришёл (null): видна() = false', function () {
    return партияИдётНаСтоле(узелСтола(true), 'сеть', null, null, false) === false;
  });

  проверка('по сети идёт, но ждём ответ сети (первая «сдаться» ещё в пути): видна() = false', function () {
    return партияИдётНаСтоле(узелСтола(true), 'сеть', null, { завершена: false }, true) === false;
  });

  /* ---------- 3. завершитьПартиюИзЛиста(): с ботом/вдвоём — в меню без записи, по сети — сдаться ---------- */

  const завершитьПартиюИзЛиста = собратьФункцию(текст, 'завершитьПартиюИзЛиста', ['режим', 'сдатьсяПоСети', 'уйтиВМеню']);

  проверка('с ботом: действие() зовёт уйтиВМеню и НЕ зовёт сдатьсяПоСети (без записи результата)', function () {
    let ушёл = false, сдался = false;
    завершитьПартиюИзЛиста('бот', function () { сдался = true; }, function () { ушёл = true; });
    return ушёл === true && сдался === false;
  });

  проверка('вдвоём на одном телефоне: действие() зовёт уйтиВМеню и НЕ зовёт сдатьсяПоСети', function () {
    let ушёл = false, сдался = false;
    завершитьПартиюИзЛиста('вдвоём', function () { сдался = true; }, function () { ушёл = true; });
    return ушёл === true && сдался === false;
  });

  проверка('по сети: действие() шлёт сдатьсяПоСети() и НЕ уходит в меню напрямую', function () {
    let ушёл = false, сдался = false;
    завершитьПартиюИзЛиста('сеть', function () { сдался = true; }, function () { ушёл = true; });
    return сдался === true && ушёл === false;
  });

  /* ---------- 4. текстЗавершенияПартии(): свой текст последствия на каждый режим ---------- */

  const текстЗавершенияПартии = собратьФункцию(текст, 'текстЗавершенияПартии', ['режим']);

  проверка('текст последствия с ботом — «без записи результата»', function () {
    return текстЗавершенияПартии('бот') === 'Партия прервётся, результат не запишется.';
  });

  проверка('текст последствия вдвоём на одном телефоне — «без результата»', function () {
    return текстЗавершенияПартии('вдвоём') === 'Партия закончится без результата.';
  });

  проверка('текст последствия по сети — «поражение, сопернику победа»', function () {
    return текстЗавершенияПартии('сеть') === 'Засчитается поражение, сопернику — победа.';
  });

  return { строки: строки, ошибок: ошибок };
}

const текст = fs.readFileSync(путьКФайлу, 'utf8');
console.log('=== Проверка двери «завершить» на столе нард (файл: ' + путьКФайлу + ') ===');
const { строки, ошибок } = прогнатьПроверки(текст);
строки.forEach(function (с) { console.log(с); });
console.log('');
console.log('Итого проверок: ' + строки.length + ', провалов: ' + ошибок);
process.exitCode = ошибок ? 1 : 0;
