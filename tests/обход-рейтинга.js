/** Единая точка учёта булевых проверок — печатает и красит итог. */
function проверить(состояние, ширина, имя, условие, детали) {
  проверок++;
  if (условие) {
    console.log('  ок    — ' + состояние + ' ' + ширина + ': ' + имя);
    return true;
  }
  провалов++;
  const строка = 'ПЛОХО — ' + состояние + ' ' + ширина + ': ' + имя + (детали ? ' (' + детали + ')' : '');
  console.log(строка);
  находки.push(строка);
  return false;
}

/** Список находок одной категории (пересечения, обрезки…) — по строке на каждую. */
function записатьНаходки(состояние, ширина, описаниеКатегории, список) {
  проверок++;
  if (!список.length) {
    console.log('  ок    — ' + состояние + ' ' + ширина + ': ' + описаниеКатегории + ' — не найдено');
    return;
  }
  провалов++;
  список.forEach((деталь) => {
    const строка = 'ПЛОХО — ' + состояние + ' ' + ширина + ': ' + описаниеКатегории + ' — ' + деталь;
    console.log(строка);
    находки.push(строка);
  });
}

