/* ---------------------------------------------------------------------
   Открыть страницу на СВОЁМ временном сервере, подделать Telegram и
   дверь /рейтинг, дойти до открытого экрана рейтинга.
   --------------------------------------------------------------------- */

async function открытьСтраницу(браузер, ширина, состояние, адрес) {
  const viewport = { width: ширина, height: ширина < 700 ? 844 : 1000 };
  const контекст = await браузер.newContext({ viewport: viewport, hasTouch: ширина < 700 });
  const страница = await контекст.newPage();

  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const т = м.text();
    const откуда = (м.location() && м.location().url) || '';
    if (/telegram-web-app\.js|telegram\.org/.test(т) || /telegram-web-app\.js|telegram\.org/.test(откуда)) return;
    красные.push('консоль: ' + т + (откуда ? ' (' + откуда + ')' : ''));
  });
  страница.on('requestfailed', (з) => {
    const адресЗапроса = з.url();
    if (/telegram-web-app\.js|telegram\.org/.test(адресЗапроса)) return;
    красные.push('сеть: ' + адресЗапроса + ' — ' + (з.failure() && з.failure().errorText));
  });

  await подготовитьПодделку(страница, { версия: '8.0' });

  // Только дверь /рейтинг — style.css подменяет сам временный сервер страниц.
  await перехватить(страница, new RegExp('/рейтинг(?:\\?|$)'), function (путь, запрос) {
    let игра = 'дурак';
    try {
      const тело = JSON.parse((запрос.postData && запрос.postData()) || '{}');
      if (тело && тело.игра) игра = тело.игра;
    } catch (о) { /* тела может не быть */ }
    путь.fulfill({ status: 200, contentType: 'application/json; charset=utf-8', body: JSON.stringify(состояние.ответ(игра)) });
  });

  await страница.goto(адрес + '/index.html');
  await страница.waitForTimeout(600);

  return { контекст: контекст, страница: страница, красные: красные };
}

/* ---------------------------------------------------------------------
   Автоматический поиск поломок вида — одним page.evaluate.
   --------------------------------------------------------------------- */

async function собратьЗамеры(страница) {
  return страница.evaluate(() => {
    function путьДо(эл) {
      if (эл.id) return '#' + эл.id;
      const кл = (эл.className && typeof эл.className === 'string') ? эл.className.trim().split(/\s+/)[0] : '';
      const текст = (эл.textContent || '').trim().slice(0, 24).replace(/\s+/g, ' ');
      return эл.tagName.toLowerCase() + (кл ? '.' + кл : '') + (текст ? ' «' + текст + '»' : '');
    }

    function видимЛи(эл, rect) {
      if (rect.width <= 0 || rect.height <= 0) return false;
      const с = getComputedStyle(эл);
      if (с.visibility === 'hidden' || с.display === 'none' || parseFloat(с.opacity) === 0) return false;
      return true;
    }

    const ИНТЕРАКТИВНЫЙ_СЕЛЕКТОР = 'button, a, input, select, textarea, [role="button"]';

    /* Элемент участвует в сравнении на пересечения, только если он
       РЕАЛЬНО СВЕРХУ в своей же точке: document.elementFromPoint(центр)
       возвращает сам элемент или его потомка. Если центр закрыт ЧЕМ
       УГОДНО другим — не важно, интерактивным или нет — элемент туда
       физически не попадёт пальцем и в сравнение не идёт: накрытое
       шторкой не считается «наездом» (задание штаба 23.09, находка
       «шторка-выбор-игры» — прежняя версия смотрела, интерактивен ли
       верхний элемент, и из-за этого пункты шторки ложно «пересекались»
       с накрытыми ею кнопкой выбора игры, «Моё место» и нижними
       вкладками). Настоящий наезд одной кнопки на другую (баг «а» из
       ломающего режима) при этом не теряется: у «Мои друзья» и
       «Добавить друга» СВОИ разные центры, оба остаются каждый в своей
       точке «сверху», и их пересечение по прямоугольникам ловит
       геометрическая проверка ниже. */
    function элементРеальноСверху(эл, rect) {
      const cx = rect.left + rect.width / 2;
      const cy = rect.top + rect.height / 2;
      if (cx < 0 || cy < 0 || cx > window.innerWidth || cy > window.innerHeight) return false; // за экраном — отдельная проверка (г)
      const верхний = document.elementFromPoint(cx, cy);
      if (!верхний) return false;
      return верхний === эл || эл.contains(верхний) || верхний.contains(эл);
    }

    const заметные = [];
    Array.prototype.slice.call(document.querySelectorAll('*')).forEach(function (эл) {
      if (эл.tagName === 'SCRIPT' || эл.tagName === 'STYLE' || эл.tagName === 'HEAD') return;
      const rect = эл.getBoundingClientRect();
      if (!видимЛи(эл, rect)) return;
      const прямойТекст = Array.prototype.slice.call(эл.childNodes)
        .some((n) => n.nodeType === 3 && n.textContent.trim().length > 0);
      заметные.push({ эл: эл, rect: rect, прямойТекст: прямойТекст });
    });

    // а) интерактивные элементы, видимые и не закрытые чужим сверху
    const интерактивныеТеги = { BUTTON: 1, A: 1, INPUT: 1, SELECT: 1, TEXTAREA: 1 };
    const интерактивные = [];
    заметные.forEach(function (з) {
      const эл = з.эл;
      const интерактивен = интерактивныеТеги[эл.tagName] || эл.getAttribute('role') === 'button';
      if (!интерактивен) return;
      if (!элементРеальноСверху(эл, з.rect)) return;
      интерактивные.push({
        эл: эл, путь: путьДо(эл), tag: эл.tagName.toLowerCase(),
        top: з.rect.top, bottom: з.rect.bottom, left: з.rect.left, right: з.rect.right
      });
    });

    const пересечения = [];
    for (let i = 0; i < интерактивные.length; i++) {
      for (let j = i + 1; j < интерактивные.length; j++) {
        const a = интерактивные[i], b = интерактивные[j];
        const пересекаются = a.left < b.right && b.left < a.right && a.top < b.bottom && b.top < a.bottom;
        if (!пересекаются) continue;
        const aВнутриB = b.left <= a.left && b.right >= a.right && b.top <= a.top && b.bottom >= a.bottom;
        const bВнутриA = a.left <= b.left && a.right >= b.right && a.top <= b.top && a.bottom >= b.bottom;
        if (aВнутриB || bВнутриA) continue;
        пересечения.push(a.путь + ' × ' + b.путь);
      }
    }

    // д) тесный зазор между кнопками (button/a), стоящими друг под другом.
    // Порог 4px внутри одного вертикального списка (общий непосредственный
    // родитель — как пункты шторки выбора игры, там 6px задуман нарочно),
    // иначе 8px между разными, не связанными в список кнопками.
    const кнопки = интерактивные.filter((э) => э.tag === 'button' || э.tag === 'a');
    const тесныЗазоры = [];
    for (let i = 0; i < кнопки.length; i++) {
      for (let j = 0; j < кнопки.length; j++) {
        if (i === j) continue;
        const a = кнопки[i], b = кнопки[j];
        const overlapX = Math.min(a.right, b.right) - Math.max(a.left, b.left);
        if (overlapX <= 0) continue;
        if (b.top < a.bottom) continue; // пересекаются или b выше a — не «под», либо уже поймано пунктом а
        const gap = b.top - a.bottom;
        const одинСписок = Boolean(a.эл.parentElement) && a.эл.parentElement === b.эл.parentElement;
        const порог = одинСписок ? 4 : 8;
        if (gap >= 0 && gap < порог) {
          тесныЗазоры.push(a.путь + ' — ' + b.путь + ' (зазор ' + Math.round(gap) + 'px, порог ' + порог + 'px' +
            (одинСписок ? ', один список' : '') + ')');
        }
      }
    }

    // б) обрезанный текст без многоточия
    const обрезанные = [];
    заметные.forEach(function (з) {
      if (!з.прямойТекст) return;
      const эл = з.эл;
      const разница = эл.scrollWidth - эл.clientWidth;
      if (разница <= 2) return;
      const с = getComputedStyle(эл);
      if (с.textOverflow === 'ellipsis') return;
      обрезанные.push(путьДо(эл) + ' (scrollWidth=' + эл.scrollWidth + ', clientWidth=' + эл.clientWidth + ')');
    });

    // в) горизонтальная прокрутка страницы. Замерено руками (диагностика
    // тестировщика 23.09): «#приложение» — position:fixed на весь экран,
    // и по правилам CSS position:fixed НАЧИСТО исключает содержимое из
    // расчёта scrollWidth любого предка — html.scrollWidth и
    // body.scrollWidth остаются равны clientWidth ВСЕГДА, сколько бы
    // контент внутри «#приложение» ни раздувался (проверено: раздутый
    // #экран-рейтинга-игроков до 2000px давал html/body.scrollWidth=390,
    // а #приложение.scrollWidth=2000, на той же странице). Значит мерить
    // нужно САМО «#приложение» — оно и есть видимый на экране прямоугольник.
    const приложение = document.getElementById('приложение');
    const scrollWidthПриложения = приложение ? приложение.scrollWidth : document.documentElement.scrollWidth;
    const scrollWidth = Math.max(document.documentElement.scrollWidth, document.body ? document.body.scrollWidth : 0, scrollWidthПриложения);
    const clientWidth = window.innerWidth;
    const прокруткаЕсть = scrollWidth > clientWidth + 1;

    // г) элементы за краем экрана
    const заЭкраном = [];
    заметные.forEach(function (з) {
      if (з.rect.left < -1 || з.rect.right > window.innerWidth + 1) {
        заЭкраном.push(путьДо(з.эл) + ' (left=' + Math.round(з.rect.left) + ', right=' + Math.round(з.rect.right) +
          ', ширина окна=' + window.innerWidth + ')');
      }
    });

    return {
      пересечения: пересечения, тесныЗазоры: тесныЗазоры, обрезанные: обрезанные,
      прокруткаЕсть: прокруткаЕсть,
      прокруткаДеталь: 'scrollWidth #приложение=' + scrollWidthПриложения + ', innerWidth=' + clientWidth,
      заЭкраном: заЭкраном, всегоИнтерактивных: интерактивные.length
    };
  });
}

/* ---------------------------------------------------------------------
   Подиум, шапка таблицы и конец списка — задание штаба 23.09 (жалоба
   владельца, пункты «з», «и», «к» из шапки файла). Отдельная функция,
   не часть «собратьЗамеры» выше: та работает одинаково для ЛЮБОГО
   состояния, а тут нужны узлы, которых у большинства состояний вовсе
   нет (шапка таблицы, подпись конца списка).
   --------------------------------------------------------------------- */

async function собратьЗамерыПодиума(страница) {
  return страница.evaluate(function () {
    function путьДо(эл) {
      if (!эл) return 'ничего';
      if (эл.id) return '#' + эл.id;
      const кл = (эл.className && typeof эл.className === 'string') ? эл.className.trim().split(/\s+/)[0] : '';
      return эл.tagName.toLowerCase() + (кл ? '.' + кл : '');
    }

    const результат = {
      карточекПодиума: 0, карточкиПерекрыты: [],
      шапкаЕсть: false, шапкаНеВЛинию: [],
      конецСпискаЕсть: false, конецСпискаТекст: null, конецСпискаНевиден: [],
      кнопкаПоказатьЕщёЕсть: false
    };

    // к) (правка владельца 25.09) кнопки «Показать ещё» на экране больше
    // не бывает ни при каких условиях — список докатывается сам при
    // прокрутке. Ищем по ТЕКСТУ, а не по id: если её вернули по ошибке
    // назад под старым или новым именем узла, находка обязана поймать её.
    const кнопкаПоказатьЕщё = Array.prototype.slice.call(document.querySelectorAll('button'))
      .find(function (б) { return б.textContent.trim() === 'Показать ещё'; });
    результат.кнопкаПоказатьЕщёЕсть = Boolean(кнопкаПоказатьЕщё);

    // з) низ каждой карточки подиума обязан оставаться «своим» по
    // document.elementFromPoint — иначе следующий блок (шапка таблицы)
    // наехал на подиум снизу (жалоба владельца: «карточки обрезаны»).
    const карточки = Array.prototype.slice.call(document.querySelectorAll('.рейтинг-подиум-карточка'));
    результат.карточекПодиума = карточки.length;
    карточки.forEach(function (карточка) {
      const rect = карточка.getBoundingClientRect();
      if (rect.width <= 0 || rect.height <= 0) return;
      const cx = rect.left + rect.width / 2;
      // Сперва проверяем ЦЕНТР самой карточки — тем же приёмом, что и
      // пункт «а» выше (пересечения): если центр не «свой», карточку
      // целиком накрыл посторонний оверлей (шторка выбора игры, окно
      // «i»), и то, что «сверху» нашлось и на её нижнем крае, — не наезд
      // СЛЕДУЮЩЕГО БЛОКА снизу, а честная модалка поверх всего экрана,
      // не баг подиума. Находка 23.09 (второй прогон): без этой проверки
      // состояния «шторка-выбор-игры»/«окно-i» краснели там, где ничего
      // не сломано — карточки лежат ПОД оверлеем целиком, не только с краю.
      const centerY = Math.min(Math.max(rect.top + rect.height / 2, 0), window.innerHeight - 1);
      const вЦентре = document.elementFromPoint(cx, centerY);
      const карточкаВидна = Boolean(вЦентре) && (вЦентре === карточка || карточка.contains(вЦентре));
      if (!карточкаВидна) return;

      const cy = Math.min(rect.bottom - 1, window.innerHeight - 1);
      if (cy < 0) return;
      const верхний = document.elementFromPoint(cx, cy);
      const своя = Boolean(верхний) && (верхний === карточка || карточка.contains(верхний));
      if (!своя) {
        результат.карточкиПерекрыты.push('место=' + карточка.getAttribute('data-место') +
          ': низ карточки перекрыт «' + путьДо(верхний) + '»');
      }
    });

    // и) подписи шапки таблицы («Место»/«Игрок»/«Очки»/«Партий») стоят
    // на одной горизонтальной линии — сверяем вертикальный центр каждой
    // с первой найденной, допуск 2px.
    const шапка = document.querySelector('.рейтинг-строка--шапка');
    результат.шапкаЕсть = Boolean(шапка);
    if (шапка) {
      const метки = ['.рейтинг-место', '.рейтинг-имя', '.рейтинг-очки', '.рейтинг-победы'];
      const центры = [];
      метки.forEach(function (селектор) {
        const узел = шапка.querySelector(селектор);
        if (!узел) return;
        const r = узел.getBoundingClientRect();
        if (r.width <= 0 || r.height <= 0) return;
        центры.push({ метка: селектор, центр: r.top + r.height / 2 });
      });
      if (центры.length > 1) {
        const базовыйЦентр = центры[0].центр;
        центры.forEach(function (з) {
          if (Math.abs(з.центр - базовыйЦентр) > 2) {
            результат.шапкаНеВЛинию.push(з.метка + ': центр ' + Math.round(з.центр) +
              'px, а у ' + центры[0].метка + ' — ' + Math.round(базовыйЦентр) + 'px');
          }
        });
      }
    }

    // к) подпись конца списка («Все игроки показаны» / «Показаны первые
    // N») видима целиком: opacity не притушен ни у неё, ни у предков,
    // и прямоугольник подписи не обрезан overflow:hidden/clip предка.
    const конецСписка = document.querySelector('.рейтинг-список-конец__итог');
    результат.конецСпискаЕсть = Boolean(конецСписка);
    if (конецСписка) {
      результат.конецСпискаТекст = конецСписка.textContent.trim();
      let узел = конецСписка;
      let проблема = null;
      while (узел && узел !== document.documentElement) {
        const стиль = getComputedStyle(узел);
        if (parseFloat(стиль.opacity) < 0.99) {
          проблема = 'opacity ' + стиль.opacity + ' у «' + путьДо(узел) + '»';
          break;
        }
        узел = узел.parentElement;
      }
      if (!проблема) {
        const rectТекста = конецСписка.getBoundingClientRect();
        let предок = конецСписка.parentElement;
        while (предок && предок !== document.documentElement) {
          const стильП = getComputedStyle(предок);
          if (/^(hidden|clip)$/.test(стильП.overflowY) || /^(hidden|clip)$/.test(стильП.overflow)) {
            const rectП = предок.getBoundingClientRect();
            if (rectТекста.bottom > rectП.bottom + 0.5 || rectТекста.top < rectП.top - 0.5) {
              проблема = 'обрезан overflow предка «' + путьДо(предок) + '» (текст ' +
                Math.round(rectТекста.top) + '–' + Math.round(rectТекста.bottom) + ', предок ' +
                Math.round(rectП.top) + '–' + Math.round(rectП.bottom) + ')';
              break;
            }
          }
          предок = предок.parentElement;
        }
      }
      if (проблема) результат.конецСпискаНевиден.push(проблема);
    }

    return результат;
  });
}

/* ---------------------------------------------------------------------
   Один прогон: состояние × ширина. Снимок кладётся на диск и в общий
   массив «снимки» (буфер + хэш) — по нему после всего прогона ищем
   совпадения РАЗНЫХ состояний (приоритетная проверка штаба).
   --------------------------------------------------------------------- */

async function прогонСостояния(браузер, состояние, ширина, адрес, снимки) {
  const метка = состояние.имя;
  let контекст = null;
  try {
    const открытое = await открытьСтраницу(браузер, ширина, состояние, адрес);
    контекст = открытое.контекст;
    const страница = открытое.страница;
    const красные = открытое.красные;

    if (!await убедитьсяЧтоУзелЕсть(страница, метка, ширина, '#кнопка-вкладка-профиль', 'кнопка «Рейтинг» в нижней панели')) return;
    if (!await кликНеЗависая(страница, метка, ширина, '#кнопка-вкладка-профиль', 'кнопка «Рейтинг» в нижней панели')) return;
    const экранПоявился = await страница.waitForSelector('#экран-рейтинга-игроков.экран--виден', { timeout: ТАЙМАУТ_ДЕЙСТВИЯ }).catch(() => null);
    if (!проверить(метка, ширина, 'экран рейтинга открылся после клика по кнопке', Boolean(экранПоявился))) return;
    await страница.waitForTimeout(700); // дать сетевому ответу и отрисовке дойти до конца, см. шапку файла

    if (состояние.действие) {
      const действиеУдалось = await состояние.действие(страница, метка, ширина);
      if (!действиеУдалось) {
        // Узел действия не нашёлся — уже записано отдельным ПЛОХО внутри
        // самого действия; дальнейшие замеры для этого сочетания бессмысленны.
        записатьНаходки(метка, ширина, 'ошибки в консоли', красные);
        return;
      }
    }

    const замеры = await собратьЗамеры(страница);
    записатьНаходки(метка, ширина, 'пересекаются интерактивные элементы', замеры.пересечения);
    записатьНаходки(метка, ширина, 'обрезанный текст без многоточия', замеры.обрезанные);
    записатьНаходки(метка, ширина, 'зазор меньше 8px между кнопками', замеры.тесныЗазоры);
    записатьНаходки(метка, ширина, 'элемент вылезает за край экрана', замеры.заЭкраном);
    проверить(метка, ширина, 'нет горизонтальной прокрутки страницы', !замеры.прокруткаЕсть, замеры.прокруткаДеталь);
    записатьНаходки(метка, ширина, 'ошибки в консоли', красные);

    // Подиум / шапка таблицы / конец списка — задание штаба 23.09.
    const замерыПодиума = await собратьЗамерыПодиума(страница);
    записатьНаходки(метка, ширина, 'низ карточки подиума перекрыт следующим блоком', замерыПодиума.карточкиПерекрыты);
    записатьНаходки(метка, ширина, 'подписи шапки таблицы не на одной линии', замерыПодиума.шапкаНеВЛинию);
    записатьНаходки(метка, ширина, 'подпись конца списка притушена или обрезана', замерыПодиума.конецСпискаНевиден);
    if (typeof состояние.ожидаетсяПодиумКарточек === 'number') {
      проверить(метка, ширина, 'на подиуме ровно ' + состояние.ожидаетсяПодиумКарточек + ' карточка(и)',
        замерыПодиума.карточекПодиума === состояние.ожидаетсяПодиумКарточек,
        'найдено: ' + замерыПодиума.карточекПодиума);
    }
    if (typeof состояние.ожидаетсяШапка === 'boolean') {
      проверить(метка, ширина, состояние.ожидаетсяШапка
        ? 'шапка таблицы показана (под подиумом есть строки)'
        : 'шапка таблицы НЕ показана (под подиумом нет ни одной строки)',
        замерыПодиума.шапкаЕсть === состояние.ожидаетсяШапка,
        'шапкаЕсть=' + замерыПодиума.шапкаЕсть);
    }
    if (состояние.ожидаетсяКонецСпискаНет) {
      // Правка владельца 25.09: подписей «Все игроки показаны»/«Показаны
      // первые N» и кнопки «Показать ещё» на этом экране больше нет вовсе —
      // список сам докатывается до 100 строк при обычной прокрутке.
      проверить(метка, ширина, 'подписи конца списка нет (владелец 25.09 убрал её совсем)',
        !замерыПодиума.конецСпискаЕсть, 'найден текст: ' + JSON.stringify(замерыПодиума.конецСпискаТекст));
      проверить(метка, ширина, 'кнопки «Показать ещё» нет (владелец 25.09 убрал её совсем)',
        !замерыПодиума.кнопкаПоказатьЕщёЕсть);
    }

    const путьСнимка = path.join(ПАПКА_СНИМКОВ, метка + '-' + ширина + '.png');
    const буфер = await страница.screenshot();
    fs.writeFileSync(путьСнимка, буфер);
    const хэш = crypto.createHash('sha1').update(буфер).digest('hex');
    снимки.push({ имя: метка, ширина: ширина, хэш: хэш, путь: путьСнимка });
  } catch (ошибка) {
    проверок++; провалов++;
    const строка = 'ПЛОХО — ' + метка + ' ' + ширина + ': проверка упала — ' + (ошибка && ошибка.message || ошибка);
    console.log(строка);
    находки.push(строка);
  } finally {
    if (контекст) await контекст.close().catch(() => null);
  }
}

/* ---------------------------------------------------------------------
   Приоритетная проверка штаба: два РАЗНЫХ состояния с одинаковым (той же
   ширины) снимком — ПЛОХО, а не «ну, просто похожие». Идёт сразу после
   основного прогона, как только снимки собраны — раньше физически
   нельзя, снимков ещё нет.
   --------------------------------------------------------------------- */

function проверитьОдинаковыеСнимки(снимки) {
  console.log('\n=== Приоритетная проверка: одинаковые снимки РАЗНЫХ состояний ===');
  let нашлиСовпадение = false;
  for (const ширина of ШИРИНЫ) {
    const наШирине = снимки.filter((с) => с.ширина === ширина);
    for (let i = 0; i < наШирине.length; i++) {
      for (let j = i + 1; j < наШирине.length; j++) {
        const a = наШирине[i], b = наШирине[j];
        проверок++;
        if (a.хэш === b.хэш) {
          нашлиСовпадение = true;
          провалов++;
          const строка = 'ПЛОХО — совпадение снимков на ширине ' + ширина + ': «' + a.имя + '» и «' + b.имя +
            '» — байт в байт одинаковые (хэш ' + a.хэш.slice(0, 12) + '…, файлы ' + path.basename(a.путь) + ' / ' + path.basename(b.путь) + ')';
          console.log(строка);
          находки.push(строка);
        } else {
          console.log('  ок    — ширина ' + ширина + ': «' + a.имя + '» ≠ «' + b.имя + '» (снимки разные)');
        }
      }
    }
  }
  if (!нашлиСовпадение) console.log('  ни одной пары совпавших снимков не нашлось — состояния визуально различаются.');
}

