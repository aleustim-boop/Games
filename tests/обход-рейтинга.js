/* ---------------------------------------------------------------------
   Действия состояний — клик по узлу с обязательной проверкой, что узел
   вообще нашёлся (правило штаба: ноль найденного — провал, не пропуск).
   Все клики — с укороченным таймаутом (8с вместо дефолтных 30с): узел
   не нашёлся/не дождался — быстрый внятный провал, а не долгое висение.
   --------------------------------------------------------------------- */

const ТАЙМАУТ_ДЕЙСТВИЯ = 8000;

async function убедитьсяЧтоУзелЕсть(страница, состояние, ширина, селектор, описание) {
  const найден = await страница.$(селектор).catch(() => null);
  return проверить(состояние, ширина, 'узел «' + описание + '» найден (' + селектор + ')', Boolean(найден));
}

/* Находка тестировщика 23.09 (проверка сценария «наезд Мои друзья на
   Добавить друга»): «убедитьсяЧтоУзелЕсть» выше находит ПЕРВЫЙ узел
   в DOM по селектору и не смотрит, виден ли он, — а «Добавить друга»
   в разметке существует ДВАЖДЫ: динамическая кнопка внутри
   #рейтинг-таблица (js/рейтинг-экран.js «кнопкаДобавитьДруга», рисуется
   только после клика по кругу «Друзья») и статичная #кнопка-добавить-
   друга на СКРЫТОМ экране #экран-друзей (index.html:768, вход «Мои
   друзья» → «Добавить друга» с уже открытого списка друзей). Пока
   действие идёт ПОСЛЕ клика по кругу «Друзья», первым в DOM-порядке
   находится именно видимая кнопка (проверено: #экран-рейтинга-игроков
   в разметке раньше #экран-друзей, поэтому её потомки раньше в дереве
   независимо от времени вставки) — но полагаться на этот порядок
   селектором 'button:has-text(...)' без экрана рискованно: переставь
   секции в index.html или вызови действие раньше отрисовки — и найдётся
   скрытый дубль с id, у которого boundingBox() всегда null. Поэтому
   ниже — своя, более строгая проверка: селектор сузен до узла ВНУТРИ
   #рейтинг-таблица (однозначно исключает дубль на другом экране) и
   явно проверяется видимость (boundingBox() !== null), а не только
   факт существования в DOM. */
async function убедитьсяЧтоУзелВидим(страница, состояние, ширина, селектор, описание) {
  const узел = await страница.$(селектор).catch(() => null);
  if (!проверить(состояние, ширина, 'узел «' + описание + '» найден (' + селектор + ')', Boolean(узел))) return null;
  const рамка = await узел.boundingBox().catch(() => null);
  if (!проверить(состояние, ширина, 'узел «' + описание + '» виден на экране (boundingBox не пуст)', Boolean(рамка))) return null;
  return узел;
}

/** Клик с укороченным таймаутом и понятным провалом вместо голого Timeout 30000ms. */
async function кликНеЗависая(страница, состояние, ширина, селектор, описание) {
  try {
    await страница.click(селектор, { timeout: ТАЙМАУТ_ДЕЙСТВИЯ });
    return true;
  } catch (ошибка) {
    проверить(состояние, ширина, 'клик по «' + описание + '» удался (' + селектор + ')', false,
      'не дождался: ' + (ошибка && ошибка.message ? ошибка.message.split('\n')[0] : ошибка));
    return false;
  }
}

