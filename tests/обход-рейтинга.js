function создатьИспорченныйStyleCss() {
  const оригинал = fs.readFileSync(ПУТЬ_СТИЛЯ, 'utf8');
  const маркерА = '#экран-рейтинга-игроков .рейтинг-круг__друзья {';
  if (оригинал.indexOf(маркерА) === -1) {
    throw new Error('Поломка «а»: в style.css не нашёлся селектор «' + маркерА + '» — ' +
      'похоже, кнопку «Мои друзья» переименовали, поломку нужно поправить вслед за ней.');
  }
  const маркерБ = '#экран-рейтинга-игроков {';
  if (оригинал.indexOf(маркерБ) === -1) {
    throw new Error('Поломка «б»: в style.css не нашёлся селектор «' + маркерБ + '».');
  }
  return оригинал +
    '\n/* --- ломающий прогон tests/обход-рейтинга.js --- */\n' +
    '#экран-рейтинга-игроков .рейтинг-круг__друзья {\n  margin-top: -16px !important;\n}\n' +
    '#экран-рейтинга-игроков {\n  min-width: 2000px !important;\n}\n';
}

