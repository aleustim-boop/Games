'use strict';
/* Домино: за просрочившего ходит бот того уровня, который назвала комната.
   Чистый node, браузера и порта нет.

   Запуск:  node tests/домино-просрочка-уровень.js
   Что делает:
     1) находит позицию, где «лёгкий», «обычный» и «сложный» ходят по-разному
        (иначе проверка ничего бы не ловила), и для каждого уровня сверяет:
        ход по просрочке == ход бота этого уровня;
     2) без второго довода, с не-функцией, с функцией, вернувшей пустое или
        мусор, и с функцией, бросившей исключение, ход делается по-старому
        (уровнем «обычный») и без исключения;
     3) ломающий запуск: копия server/игры/домино.js во временной папке системы,
        в которой второй довод снова игнорируется; та же проверка на копии
        (довод --модуль <путь>) обязана покраснеть. Настоящий файл не трогаем.
   Код выхода: 0 — всё зелено; 1 — провал; 2 — место порчи не нашлось
   (значит, модуль переделали, и ломающий запуск надо обновить). */
const assert = require('node:assert/strict');
const path = require('node:path');
const os = require('node:os');
const fs = require('node:fs');
const { spawnSync } = require('node:child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const НАСТОЯЩИЙ = path.join(КОРЕНЬ, 'server', 'игры', 'домино.js');
const МИНИМУМ_ПРОВЕРОК = 20;  // меньше — значит, часть проверок молча выпала

const номерДовода = process.argv.indexOf('--модуль');
const путьКопии = номерДовода > 0 ? process.argv[номерДовода + 1] : null;

// Рейтинг комнаты (если подтянется через цепочку require) пишет на диск — уводим во временную папку.
process.env.ДАННЫЕ_ИГРЫ = path.join(os.tmpdir(), 'domino-uroven-' + process.pid);

const Д = require(путьКопии ? path.resolve(путьКопии) : НАСТОЯЩИЙ);
const П = require(path.join(КОРЕНЬ, 'игры', 'домино', 'домино-правила'));
const Б = require(path.join(КОРЕНЬ, 'игры', 'домино', 'домино-бот'));

let проверок = 0;
let провалов = 0;
function проверка(имя, дело) {
  проверок++;
  try { дело(); console.log('  ок      ' + имя); }
  catch (e) { провалов++; console.log('  ПРОВАЛ  ' + имя + ' — ' + (e && e.message)); }
}

const УРОВНИ = ['лёгкий', 'обычный', 'сложный'];
const КЛЮЧИ = ['и1', 'и2', 'и3'];

/* Бот «лёгкий» ходит случайно — на время сравнения Math.random зафиксирован,
   чтобы и бот, и ход по просрочке выбрали одно и то же. */
function сФиксированнымСлучаем(значение, дело) {
  const настоящий = Math.random;
  Math.random = () => значение;
  try { return дело(); } finally { Math.random = настоящий; }
}

/* Простой повторяемый генератор для поиска позиции: свой, а не Math.random,
   чтобы позиция каждый раз находилась одна и та же. */
function генератор(зерно) {
  let s = зерно >>> 0;
  return () => { s = (Math.imul(s, 1664525) + 1013904223) >>> 0; return s / 4294967296; };
}

const ходБота = (п, кто, уровень) => Б.ход(П.вид(п.игра, п.игроки.indexOf(кто)), уровень);
const ключХода = ход => JSON.stringify(ход);

/* Позиция, где три уровня дают три разных хода у ходящего. Ищем среди
   партий, сыгранных случайно по зерну; не нашлась — это провал проверки. */
function найтиПозицию() {
  const настоящий = Math.random;
  try {
    for (let зерно = 1; зерно <= 400; зерно++) {
      Math.random = генератор(зерно);
      const п = Д.раздать(null, { игроки: КЛЮЧИ.slice(), цельДомино: 50 });
      for (let шаг = 0; шаг < 80 && п.игра.фаза === 'игра'; шаг++) {
        const кто = Д.чейХод(п);
        const ходы = УРОВНИ.map(у => сФиксированнымСлучаем(0.999, () => ключХода(ходБота(п, кто, у))));
        if (new Set(ходы).size === 3 && ходБота(п, кто, 'обычный').действие === 'кость') return JSON.parse(JSON.stringify(п));
        const ход = ходБота(п, кто, 'лёгкий');
        if (!ход || !Д.сделатьХод(п, кто, ход).принято) break;
      }
    }
  } finally { Math.random = настоящий; }
  return null;
}

/* Копия позиции, у которой время хода давно вышло. */
function просроченная(позиция) {
  const п = JSON.parse(JSON.stringify(позиция));
  п.началоХода = Date.now() - 10 * 60 * 1000;
  return п;
}

/* Что должно получиться: тот же ход, сделанный ботом заданного уровня. */
function ожидаемоеСостояние(позиция, уровень) {
  const п = JSON.parse(JSON.stringify(позиция));
  const кто = Д.чейХод(п);
  const ход = сФиксированнымСлучаем(0.999, () => ходБота(п, кто, уровень));
  assert.ok(Д.сделатьХод(п, кто, ход).принято, 'эталонный ход не принят');
  return JSON.stringify(п.игра);
}

function просрочкаС(позиция, второйДовод, число = 1) {
  const п = просроченная(позиция);
  const кто = Д.чейХод(п);
  const ответ = сФиксированнымСлучаем(0.999, () => (число === 1 ? Д.ходПоПросрочке(п, второйДовод) : Д.ходПоПросрочке(п)));
  assert.ok(ответ, 'ход по просрочке не сделан');
  assert.equal(ответ.ктоСделал, кто);
  return JSON.stringify(п.игра);
}

console.log('Домино: уровень бота при ходе по просрочке' + (путьКопии ? ' (КОПИЯ: ' + путьКопии + ')' : ''));

const позиция = найтиПозицию();
проверка('нашлась позиция, где три уровня ходят по-разному', () => assert.ok(позиция, 'такой позиции нет — проверка ничего бы не ловила'));

if (позиция) {
  const прежний = ожидаемоеСостояние(позиция, 'обычный');

  for (const уровень of УРОВНИ) {
    проверка('уровень «' + уровень + '»: ход по просрочке совпадает с ходом бота этого уровня', () => {
      assert.equal(просрочкаС(позиция, () => уровень), ожидаемоеСостояние(позиция, уровень));
    });
  }

  проверка('три уровня дали три разных итоговых состояния стола', () => {
    assert.equal(new Set(УРОВНИ.map(у => ожидаемоеСостояние(позиция, у))).size, 3);
  });

  проверка('функцию спрашивают про того, чей сейчас ход', () => {
    const спрошенные = [];
    const п = просроченная(позиция);
    const кто = Д.чейХод(п);
    Д.ходПоПросрочке(п, имя => { спрошенные.push(имя); return 'сложный'; });
    assert.deepEqual(спрошенные, [кто]);
  });

  const старыйХод = [
    ['второго довода нет', undefined, 0],
    ['довод — не функция (строка)', 'сложный'],
    ['довод — не функция (объект)', { уровень: 'сложный' }],
    ['довод — null', null],
    ['функция вернула null', () => null],
    ['функция вернула undefined', () => undefined],
    ['функция вернула пустую строку', () => ''],
    ['функция вернула число', () => 42],
    ['функция вернула объект', () => ({ уровень: 'сложный' })],
    ['функция вернула неизвестное слово', () => 'гроссмейстер'],
    ['функция вернула слово другим регистром', () => 'СЛОЖНЫЙ'],
    ['функция бросила исключение', () => { throw new Error('сбой в комнате'); }],
    ['функция бросила не Error', () => { throw 'строка'; }],
  ];
  for (const [имя, довод, число] of старыйХод) {
    проверка(имя + ': ход по-старому («обычный»), без исключения', () => {
      assert.equal(просрочкаС(позиция, довод, число === 0 ? 0 : 1), прежний);
    });
  }
}

/* ---------- Ломающий запуск ---------- */

function ломающийЗапуск() {
  console.log('Ломающий запуск на копии');
  const текст = fs.readFileSync(НАСТОЯЩИЙ, 'utf8');
  const было = 'доделатьХодЗаПросрочившего(п, кто, уровеньЗаПросрочившего(уровеньМеста, кто))';
  const стало = 'доделатьХодЗаПросрочившего(п, кто, УРОВЕНЬ_ЗА_ПРОСРОЧИВШЕГО)';
  if (!текст.includes(было)) {
    console.log('  Не нашлось место порчи в server/игры/домино.js — модуль переделали, обнови ломающий запуск.');
    return true;
  }
  // Относительные require переписываем в абсолютные: копия лежит не рядом с оригиналом.
  const испорчено = текст.replace(было, стало)
    .replace(/require\('(\.{1,2}\/[^']+)'\)/g, (_, п) => 'require(' + JSON.stringify(path.resolve(path.dirname(НАСТОЯЩИЙ), п)) + ')');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'domino-uroven-kopiya-'));
  const файл = path.join(папка, 'домино.js');
  fs.writeFileSync(файл, испорчено);
  try {
    const итог = spawnSync(process.execPath, [__filename, '--модуль', файл], { encoding: 'utf8', timeout: 60000 });
    проверка('ломающий запуск: копия с проигнорированным вторым доводом краснеет', () => {
      assert.equal(итог.status, 1, 'копия не покраснела (код выхода ' + итог.status + '): ' + (итог.stderr || '').slice(0, 200));
      assert.match(итог.stdout, /ПРОВАЛ  уровень «(лёгкий|сложный)»/);
    });
  } finally { fs.rmSync(папка, { recursive: true, force: true }); }
  return false;
}

if (!путьКопии) {
  if (ломающийЗапуск()) { console.log('Итого проверок: ' + проверок + ', провалов: ' + (провалов + 1)); process.exit(2); }
  проверка('проверок выполнено не меньше ' + МИНИМУМ_ПРОВЕРОК, () => assert.ok(проверок >= МИНИМУМ_ПРОВЕРОК, 'выполнено только ' + проверок));
}
console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
process.exit(провалов ? 1 : 0);
