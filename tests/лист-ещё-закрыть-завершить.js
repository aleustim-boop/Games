// Проверка: дверь закрытьЗавершить в общем листе «⋯» (общее/js/лист-ещё.js) закрывает
// окно «Выйти из партии?» снаружи (например, когда сетевая партия кончилась сама).
// Запуск:
//   node tests/лист-ещё-закрыть-завершить.js                — обычный прогон, ждём 0 провалов
//   node tests/лист-ещё-закрыть-завершить.js --файл <путь>  — тот же набор, но код листа
//     берётся из файла по пути (для ломающего запуска: путь ведёт на испорченную КОПИЮ
//     во временной папке; файл проекта проверка не трогает).
//   node tests/лист-ещё-закрыть-завершить.js --сломать <папка>  — ломающий запуск: сама
//     кладёт в <папку> (временную, не в проекте) три испорченные КОПИИ общее/js/лист-ещё.js:
//       1) дверь не отдана наружу; 2) дверь зовёт «Выйти»; 3) дверь не прячет окно.
//     Каждую гоняет обычным прогоном (--файл) и требует провала. Не нашла место порчи
//     в файле ровно один раз — это тоже провал (ноль найденного не бывает «всё хорошо»).
//     Выход 1, если хоть одна порча не поймана.
//
// jsdom в проекте нет, поэтому здесь лёгкий поддельный DOM — только то, чем пользуется
// лист (приём тот же, что в tests/лист-ещё-завершить.js). Модуль грузится через vm
// из текста файла.

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const КОРЕНЬ = path.join(__dirname, '..');

function аргумент(имя) {
  const индекс = process.argv.indexOf(имя);
  return индекс !== -1 ? process.argv[индекс + 1] : null;
}

const путьКФайлу = аргумент('--файл') || path.join(КОРЕНЬ, 'общее', 'js', 'лист-ещё.js');

/* ---------- лёгкий поддельный DOM ---------- */

function создатьЭлемент(тег, реестр) {
  const классы = new Set();
  const слушатели = {};
  const атрибуты = {};
  let _id = '';
  const эл = {
    tagName: тег,
    children: [],
    textContent: '',
    offsetParent: {},
    classList: {
      add: function (c) { классы.add(c); },
      remove: function (c) { классы.delete(c); },
      contains: function (c) { return классы.has(c); },
      toggle: function (c, force) {
        const есть = классы.has(c);
        const нужно = force === undefined ? !есть : Boolean(force);
        if (нужно) классы.add(c); else классы.delete(c);
      }
    },
    setAttribute: function (k, v) { атрибуты[k] = String(v); },
    getAttribute: function (k) { return (k in атрибуты) ? атрибуты[k] : null; },
    addEventListener: function (тип, fn) { (слушатели[тип] = слушатели[тип] || []).push(fn); },
    click: function () { (слушатели.click || []).forEach(function (fn) { fn({}); }); },
    appendChild: function (реб) { эл.children.push(реб); return реб; },
    querySelector: function (sel) { return найтиПоКлассу(эл, sel.replace(/^\./, '').split(':')[0]); },
    focus: function () {}
  };
  Object.defineProperty(эл, 'id', {
    get: function () { return _id; },
    set: function (значение) { _id = значение; if (реестр) реестр.set(значение, эл); }
  });
  return эл;
}

function найтиПоКлассу(корень, класс) {
  for (let i = 0; i < корень.children.length; i++) {
    const реб = корень.children[i];
    if (реб.classList.contains(класс)) return реб;
    const вложенный = найтиПоКлассу(реб, класс);
    if (вложенный) return вложенный;
  }
  return null;
}

function создатьDocument() {
  const реестр = new Map();
  const слушателиДокумента = {};
  const body = создатьЭлемент('body', реестр);
  return {
    body: body,
    createElement: function (тег) { return создатьЭлемент(тег, реестр); },
    getElementById: function (id) { return реестр.get(id) || null; },
    addEventListener: function (тип, fn) { (слушателиДокумента[тип] = слушателиДокумента[тип] || []).push(fn); }
  };
}

/** Разметка листа «⋯» с теми же id, что на страницах. */
function построитьЛист(document) {
  const кнопкаЕщё = document.createElement('button');
  кнопкаЕщё.id = 'кнопка-игра-ещё';
  document.body.appendChild(кнопкаЕщё);

  const лист = document.createElement('div');
  лист.id = 'лист-игры';
  лист.classList.add('лист-ещё');
  лист.classList.add('скрыт');
  document.body.appendChild(лист);

  const фон = document.createElement('div');
  фон.id = 'лист-игры-фон';
  лист.appendChild(фон);

  function строка(id, подпись, idСостояния) {
    const кнопка = document.createElement('button');
    кнопка.id = id;
    кнопка.classList.add('лист-ещё__строка');
    лист.appendChild(кнопка);
    const текст = document.createElement('span');
    текст.classList.add('лист-ещё__подпись');
    текст.textContent = подпись;
    кнопка.appendChild(текст);
    if (idСостояния) {
      const состояние = document.createElement('span');
      состояние.id = idСостояния;
      состояние.classList.add('лист-ещё__значение');
      кнопка.appendChild(состояние);
    }
    return кнопка;
  }

  строка('кнопка-лист-игры-меню', 'В меню');
  строка('кнопка-лист-игры-правила', 'Как играть');
  строка('кнопка-лист-игры-звук', 'Звук', 'лист-игры-звук-состояние');
  строка('кнопка-лист-игры-вибрация', 'Вибрация', 'лист-игры-вибрация-состояние');
  строка('кнопка-лист-игры-оформление', 'Оформление');
  строка('кнопка-лист-игры-рекорды', 'Рекорды');

  const кнопкаЗакрыть = document.createElement('button');
  кнопкаЗакрыть.classList.add('лист-ещё__закрыть');
  лист.appendChild(кнопкаЗакрыть);
}

function загрузитьЛистЕщё(document) {
  const исходник = fs.readFileSync(путьКФайлу, 'utf8');
  const модуль = { exports: {} };
  const песочница = { module: модуль, exports: модуль.exports, console: console, document: document };
  vm.createContext(песочница);
  vm.runInContext(исходник, песочница, { filename: путьКФайлу + ' (в памяти)' });
  return модуль.exports;
}

/* ---------- сами проверки ---------- */

function прогнатьПроверки() {
  const строки = [];
  let ошибок = 0;
  function проверка(имя, условие, подробности) {
    if (условие) {
      строки.push('OK   ' + имя);
    } else {
      ошибок++;
      строки.push('ПЛОХО ' + имя + (подробности ? ' — ' + подробности : ''));
    }
  }

  /** Лист с дверью «завершить»; счётчики говорят, что именно было вызвано. */
  function собрать() {
    const счёт = { действие: 0, продолжить: 0, пауза: 0 };
    const document = создатьDocument();
    const МодульЛиста = загрузитьЛистЕщё(document);
    построитьЛист(document);
    const api = МодульЛиста.подключить({
      двери: {
        завершить: {
          действие: function () { счёт.действие++; },
          продолжить: function () { счёт.продолжить++; },
          пауза: function () { счёт.пауза++; },
          видна: function () { return true; },
          текст: 'т'
        }
      }
    });
    return { document: document, api: api, счёт: счёт };
  }

  // 1. Дверь отдана наружу. Нет двери — остальное проверять нечем, это провал.
  const а = собрать();
  проверка('дверь закрытьЗавершить отдана наружу', typeof а.api.закрытьЗавершить === 'function');
  if (typeof а.api.закрытьЗавершить !== 'function') return { строки: строки, ошибок: ошибок };

  // 2. Без открытого окна — не падает, ничего не зовёт.
  let упала = false;
  try { а.api.закрытьЗавершить(); } catch (e) { упала = true; }
  проверка('окно не открыто: дверь не падает', !упала);
  проверка('окно не открыто: «Выйти»/«Остаться» не вызваны', а.счёт.действие === 0 && а.счёт.продолжить === 0);

  // 3. Окно открыто — дверь закрывает без «Выйти»/«Остаться».
  проверка('спроситьЗавершить открыла окно', а.api.спроситьЗавершить() === true);
  const плашка = а.document.getElementById('плашка-завершить');
  проверка('окно подтверждения есть и видно', плашка !== null && !плашка.classList.contains('скрыт'));
  if (плашка === null) return { строки: строки, ошибок: ошибок };
  проверка('при открытии позвана пауза', а.счёт.пауза === 1);
  а.api.закрытьЗавершить();
  проверка('дверь закрыла окно', плашка.classList.contains('скрыт'));
  проверка('дверь не вызвала «Выйти» (действие)', а.счёт.действие === 0);
  проверка('дверь не вызвала «Остаться» (продолжить)', а.счёт.продолжить === 0);

  // 4. Повторный вызов на закрытом окне — тоже тихо.
  упала = false;
  try { а.api.закрытьЗавершить(); } catch (e) { упала = true; }
  проверка('повторный вызов на закрытом окне не падает', !упала);

  // 5. После закрытия окно снова открывается.
  проверка('после закрытия спроситьЗавершить снова вернула true', а.api.спроситьЗавершить() === true);
  проверка('после закрытия окно снова открылось',
    а.document.getElementById('плашка-завершить') === плашка && !плашка.classList.contains('скрыт'));
  проверка('после повторного открытия пауза позвана второй раз', а.счёт.пауза === 2);

  // 6. Кнопки окна работают как раньше.
  плашка.querySelector('.плашка-завершить__да').click();
  проверка('«Выйти» после повторного открытия зовёт действие', а.счёт.действие === 1);

  // 7. Лист «⋯» дверь не трогает.
  const б = собрать();
  б.api.спроситьЗавершить();
  б.api.открыть();
  б.api.закрытьЗавершить();
  проверка('дверь не закрывает лист «⋯»', б.api.открыт());

  return { строки: строки, ошибок: ошибок };
}

/* ---------- ломающий запуск ---------- */

const ЗАКРЫТЬ_НАЧАЛО = "      узел.classList.add('скрыт');\n      дверьВПодтверждении = null;\n    }\n\n    // Тексты";

const ПОРЧИ = [
  { имя: 'дверь не отдана наружу', из: ',\n      закрытьЗавершить: закрытьЗавершить', в: '' },
  { имя: 'дверь зовёт «Выйти»', из: ЗАКРЫТЬ_НАЧАЛО,
    в: "      закрытьПодтверждение(false);\n" + ЗАКРЫТЬ_НАЧАЛО },
  { имя: 'дверь не прячет окно', из: ЗАКРЫТЬ_НАЧАЛО,
    в: "      дверьВПодтверждении = null;\n    }\n\n    // Тексты" }
];

function сломать(папка) {
  const исходник = fs.readFileSync(path.join(КОРЕНЬ, 'общее', 'js', 'лист-ещё.js'), 'utf8');
  fs.mkdirSync(папка, { recursive: true });
  let непойманных = 0;
  ПОРЧИ.forEach(function (порча, номер) {
    if (исходник.split(порча.из).length !== 2) {
      console.log('НЕ ПОЙМАНА порча ' + (номер + 1) + ' (' + порча.имя + '): место порчи в файле не найдено ровно один раз');
      непойманных++;
      return;
    }
    const копия = path.join(папка, 'порча' + (номер + 1) + '.js');
    fs.writeFileSync(копия, исходник.replace(порча.из, function () { return порча.в; }));
    const запуск = require('child_process').spawnSync(process.execPath, [__filename, '--файл', копия], { encoding: 'utf8' });
    if (запуск.status === 1) {
      console.log('поймана порча ' + (номер + 1) + ' (' + порча.имя + '): ' +
        (запуск.stdout.match(/Итого проверок: \d+, провалов: \d+/) || [''])[0]);
    } else {
      console.log('НЕ ПОЙМАНА порча ' + (номер + 1) + ' (' + порча.имя + '): выход ' + запуск.status);
      непойманных++;
    }
  });
  console.log('Порч: ' + ПОРЧИ.length + ', не поймано: ' + непойманных);
  process.exitCode = непойманных ? 1 : 0;
}

if (process.argv.includes('--сломать')) {
  const папка = аргумент('--сломать');
  if (!папка) {
    console.log('Нужна временная папка: --сломать <папка>');
    process.exitCode = 1;
  } else {
    сломать(папка);
  }
} else {
  console.log('=== Проверка двери закрытьЗавершить в общем листе (файл: ' + путьКФайлу + ') ===');
  const { строки, ошибок } = прогнатьПроверки();
  строки.forEach(function (с) { console.log(с); });
  console.log('');
  console.log('Итого проверок: ' + строки.length + ', провалов: ' + ошибок);
  process.exitCode = ошибок ? 1 : 0;
}
