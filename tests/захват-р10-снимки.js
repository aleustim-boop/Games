/* ---------- ломающие запуски на копиях ---------- */

function запуститьПорчу(имяПорчи, доводы, ждём) {
  const итог = spawnSync(process.execPath, [__filename].concat(доводы), { encoding: 'utf8' });
  const вывод = итог.stdout || '';
  const красное = итог.status === 1 && ждём.test(вывод);
  console.log((красное ? 'покраснело: ' : 'НЕ ПОКРАСНЕЛО: ') + имяПорчи + ' (код ' + итог.status + ')');
  if (process.env.ПОДРОБНО || !красное) console.log(вывод + (итог.stderr || ''));
  else console.log(вывод.split('\n').filter(с => /^ПРОВАЛ|^Итого/.test(с)).slice(0, 4).join('\n'));
  return красное;
}

function ломающийЗапуск(папка) {
  fs.mkdirSync(папка, { recursive: true });
  const стол = fs.readFileSync(path.join(КОРЕНЬ, 'игры', 'захват', 'захват-стол.js'), 'utf8');
  const стили = fs.readFileSync(path.join(КОРЕНЬ, 'игры/захват/style-захват.css'), 'utf8');
  const правилоЦвета = '.захват-число-приказа--раскрытие { color: var(--сб-текст); }';
  // Порча 1: стол берёт число стрелки из счёта только в первый раз и дальше показывает его же — число не меняется.
  const былоСтол = "сколько: пилюли[ключ], вид: 'раскрытие'";
  const стал = "сколько: ((состояние.__первое = состояние.__первое || {})[ключ] === undefined ? (состояние.__первое[ключ] = пилюли[ключ]) : состояние.__первое[ключ]), вид: 'раскрытие'";
  const мест = [[былоСтол, стол.split(былоСтол).length - 1], [правилоЦвета, стили.split(правилоЦвета).length - 1]];
  const не = мест.filter(м => м[1] !== 1);
  if (не.length) {
    не.forEach(м => console.log('ПОРЧА НЕ СДЕЛАНА: «' + м[0] + '» — мест для порчи ' + м[1] + ' (нужно ровно одно)'));
    process.exit(3);
  }
  const копияСтола = path.join(папка, 'захват-стол-сломан.js');
  fs.writeFileSync(копияСтола, стол.replace(былоСтол, () => стал));
  const копияСерое = path.join(папка, 'style-захват-серое.css');
  fs.writeFileSync(копияСерое, стили.replace(правилоЦвета, () => '.захват-число-приказа--раскрытие { color: #888888; }'));
  const копияСалат = path.join(папка, 'style-захват-салатовое.css');
  fs.writeFileSync(копияСалат, стили.replace(правилоЦвета, () => '.захват-число-приказа--раскрытие { color: #D2F76B; }'));
  const красные = [
    запуститьПорчу('стол не читает счёт.пилюли — число на стрелке не меняется', ['--стол', копияСтола], /число на стрелке упало/),
    запуститьПорчу('число на стрелке раскрытия серое, не --сб-текст', ['--css', копияСерое], /цвета --сб-текст/),
    запуститьПорчу('число на стрелке раскрытия салатовое', ['--css', копияСалат], /цвета --сб-текст|не салатовое/)
  ];
  process.exit(красные.every(Boolean) ? 0 : 2);
}

