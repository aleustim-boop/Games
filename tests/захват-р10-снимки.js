/** Выполняется в браузере: серая строка под рядом раундов. */
function замерПояснения(id) {
  const у = document.getElementById(id);
  if (!у) return { есть: false };
  const р = у.getBoundingClientRect();
  const ш = window.innerWidth;
  return {
    есть: true,
    текст: (у.textContent || '').trim(),
    видна: !у.classList.contains('скрыт') && getComputedStyle(у).display !== 'none' && р.width > 0 && р.height > 0,
    вОкне: р.left >= -0.5 && р.right <= ш + 0.5,
    необрезана: у.scrollWidth <= у.clientWidth + 1,
    серая: (() => { const ц = getComputedStyle(у).color.match(/\d+/g).map(Number); return Math.max(ц[0], ц[1], ц[2]) - Math.min(ц[0], ц[1], ц[2]) < 40; })()
  };
}

/** Ставится в страницу: следит за стрелками-раскрытием и числами на шайбах каждые 16 мс. */
function поставитьСледилку() {
  window.__сл = null;
  window.__сбросСледилки = () => {
    window.__сл = { цвета: [], ожидаемыйЦвет: null, кадров: 0, стрелокМакс: 0, макс: {}, упало: null, плохиеШайбы: [], кадровБезШайб: 0, атрибутыПлохие: 0 };
  };
  window.__сбросСледилки();
  setInterval(() => {
    const с = window.__сл;
    const стрелки = Array.from(document.querySelectorAll('.захват-число-приказа--раскрытие'));
    if (!стрелки.length) return;
    с.кадров++;
    с.стрелокМакс = Math.max(с.стрелокМакс, стрелки.length);
    const шайбы = Array.from(document.querySelectorAll('.захват-шайба__число')).map(у => (у.textContent || '').trim());
    if (!шайбы.length) с.кадровБезШайб++;
    шайбы.forEach(т => { if (!/^[0-9]+$/.test(т) && с.плохиеШайбы.length < 5) с.плохиеШайбы.push(JSON.stringify(т)); });
    if (с.цвета.length < 3) {
      // Ожидаемый цвет — у пробного узла с color: var(--сб-текст) рядом со стрелкой (тот же родитель, те же переменные).
      const проба = document.createElement('span');
      проба.style.color = 'var(--сб-текст)';
      стрелки[0].parentNode.appendChild(проба);
      с.ожидаемыйЦвет = getComputedStyle(проба).color;
      проба.remove();
      стрелки.forEach(у => с.цвета.push(getComputedStyle(у).color));
    }
    стрелки.forEach(у => {
      const из = у.getAttribute('data-из'), в = у.getAttribute('data-в'), кто = у.getAttribute('data-кто');
      if (из === null || в === null || кто === null) с.атрибутыПлохие++;
      const ключ = из + '>' + в + '>' + кто;
      const число = parseInt((у.textContent || '').trim(), 10);
      if (!(число >= 0)) { с.плохиеШайбы.push('число на стрелке ' + JSON.stringify(у.textContent)); return; }
      if (!(ключ in с.макс)) с.макс[ключ] = число;
      else if (число > с.макс[ключ]) с.макс[ключ] = число;
      else if (число < с.макс[ключ] && !с.упало) с.упало = { ключ: ключ, было: с.макс[ключ], стало: число };
    });
  }, 16);
}

/** Сейчас на столе есть стрелка, у которой число меньше, чем было, когда она появилась. */
function естьУпавшаяСейчас() {
  const с = window.__сл;
  return Array.from(document.querySelectorAll('.захват-число-приказа--раскрытие')).some(у => {
    const ключ = у.getAttribute('data-из') + '>' + у.getAttribute('data-в') + '>' + у.getAttribute('data-кто');
    return ключ in с.макс && parseInt(у.textContent, 10) < с.макс[ключ];
  });
}

