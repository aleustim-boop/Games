'use strict';

/* =====================================================================
   ПОЧЕМУ МОЛЧИТ НАДПИСЬ «Подход мимо вас — играет напарник».

   ЗАЧЕМ. За столом парами человек иногда сидит без дела: подход идёт между
   ботами, и его даже не спрашивают. На этот случай игра показывает строку
   «Подход мимо вас — играет напарник», чтобы человек не решил, что игра
   зависла. Соседняя проверка «врёт-ли-надпись-про-пару.js» ловит ЛОЖНЫЕ
   показы, но за молчание не ругает: ноль показов она считает нормой.
   А ноль показов — тоже беда: строку писали, обсуждали и чинили, а на
   экране её нет вовсе, и человек снова смотрит в тихий стол.

   ЧТО ДЕЛАЕТ ЭТОТ ФАЙЛ. Гоняет партии парами и на каждом шаге спрашивает
   у самой игры (правила.надписьПроНапарникаУместна), пора ли показывать
   надпись. Если ни разу не пора — печатает, КАКОЕ ИМЕННО из шести условий
   всё время говорит «нет». Без такой разборки штабу пришлось бы гадать.

   Считать «подходы мимо» своими руками мы нарочно не стали: игра отдаёт
   наружу свою же мерку (пересчитатьПропущенныеПодходы), и берём её —
   иначе проверка однажды разойдётся с игрой и начнёт врать.

   Запуск:  node tests/почему-молчит-надпись-про-пару.js [партий]
   ===================================================================== */

const правила = require('../js/game.js');

const ПАРТИЙ = Number(process.argv[2]) || 300;

/**
 * Какое из условий показа сказало «нет» прямо сейчас.
 * Порядок повторяет надписьПроНапарникаУместна в js/game.js.
 * Про «нападает человек или его напарник» спрашиваем через партнёр():
 * отдельной двери самИлиНапарник наружу нет.
 */
function ктоЗапретил(партия, мимо, былЯ) {
  if (!партия || !партия.парами) return 'стол не парами';
  if (партия.завершена) return 'партия уже кончилась';
  if (мимо < 2) return 'подходов мимо человека меньше двух';
  if (былЯ) return 'человек играл в этом подходе сам';
  if (правила.ктоХодит(партия) === 'человек') return 'сейчас слово человека';
  if (правила.защищается(партия) === 'человек') return 'человек отбивается';
  if (партия.атакует === 'человек' || правила.партнёр(партия, 'человек') === партия.атакует) {
    return 'нападает человек или его напарник';
  }
  const рука = партия.руки['человек'];
  if (!(рука && рука.length > 0)) return 'у человека пустая рука';
  return null;
}

function сыграть() {
  const партия = правила.создатьПартию({ игроков: 4, парами: true });
  let счёт = правила.пустойСчётПодходов();
  const запреты = {};
  const мигиПочтиГотовые = {};
  let зажиганий = 0;
  let максМимо = 0;

  for (let шаг = 0; шаг < 4000 && !партия.завершена; шаг++) {
    const чей = правила.ктоХодит(партия);
    if (!чей) break;
    /* И за человека, и за ботов ходит бот: нам важно не мастерство игры,
       а сама возможность встретить подход, идущий мимо человека. */
    if (!правила.ходБота(партия, чей)) break;

    счёт = правила.пересчитатьПропущенныеПодходы(счёт, партия);
    if (счёт.подходовМимо > максМимо) максМимо = счёт.подходовМимо;

    const горит = правила.надписьПроНапарникаУместна(
      партия, счёт.подходовМимо, счёт.былЯвПодходе);
    if (горит) зажиганий++;
    else {
      const кто = ктоЗапретил(партия, счёт.подходовМимо, счёт.былЯвПодходе);
      if (кто) запреты[кто] = (запреты[кто] || 0) + 1;
      /* Отдельно считаем самое интересное: два условия из шести уже
         выполнены (человека обошли дважды и в этом подходе он ещё не играл),
         а надписи всё равно нет. Именно тут и прячется настоящая причина. */
      if (счёт.подходовМимо >= 2 && !счёт.былЯвПодходе && !партия.завершена) {
        мигиПочтиГотовые[кто] = (мигиПочтиГотовые[кто] || 0) + 1;
      }
    }
  }
  return { зажиганий, максМимо, запреты, мигиПочтиГотовые };
}

console.log('=== Почему молчит надпись «Подход мимо вас — играет напарник» ===');
console.log('Стол: вчетвером, парами. Партий: ' + ПАРТИЙ + '\n');

let всегоЗажиганий = 0;
let партийСНадписью = 0;
let рекордМимо = 0;
const всеЗапреты = {};
const всеПочтиГотовые = {};

for (let i = 0; i < ПАРТИЙ; i++) {
  const и = сыграть();
  всегоЗажиганий += и.зажиганий;
  if (и.зажиганий > 0) партийСНадписью++;
  if (и.максМимо > рекордМимо) рекордМимо = и.максМимо;
  for (const к of Object.keys(и.запреты)) всеЗапреты[к] = (всеЗапреты[к] || 0) + и.запреты[к];
  for (const к of Object.keys(и.мигиПочтиГотовые)) {
    всеПочтиГотовые[к] = (всеПочтиГотовые[к] || 0) + и.мигиПочтиГотовые[к];
  }
}

console.log('Надпись зажигалась: ' + всегоЗажиганий + ' раз, в ' + партийСНадписью +
            ' партиях из ' + ПАРТИЙ);
console.log('Самый долгий обход человека за прогон: ' + рекордМимо + ' подходов подряд\n');
console.log('Что мешало показать надпись (шагов игры, где условие сказало «нет»):');
Object.keys(всеЗапреты)
  .sort(function (а, б) { return всеЗапреты[б] - всеЗапреты[а]; })
  .forEach(function (к) { console.log('  ' + всеЗапреты[к] + ' — ' + к); });

/* Самое важное место отчёта. Два условия из шести — «человека обошли
   дважды» и «в этом подходе он ещё не играл» — самые редкие; если они уже
   сошлись, а надписи всё равно нет, значит мешает одно из остальных, и вот
   оно-то и есть настоящая причина молчания. */
const почтиВсего = Object.keys(всеПочтиГотовые)
  .reduce(function (с, к) { return с + всеПочтиГотовые[к]; }, 0);
console.log('\nШагов, где человека уже обошли дважды И в этом подходе он ещё');
console.log('не играл, а надписи всё равно нет: ' + почтиВсего + '.');
if (почтиВсего > 0) {
  console.log('Что мешало именно в эти шаги:');
  Object.keys(всеПочтиГотовые)
    .sort(function (а, б) { return всеПочтиГотовые[б] - всеПочтиГотовые[а]; })
    .forEach(function (к) { console.log('  ' + всеПочтиГотовые[к] + ' — ' + к); });
}

console.log('\n=== Итог: ' + (всегоЗажиганий > 0
  ? 'надпись живая, показывается'
  : 'НАДПИСЬ НЕ ПОКАЗЫВАЕТСЯ НИКОГДА — смотрите список выше') + ' ===');
