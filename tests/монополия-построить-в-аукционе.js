const fs = require('fs');
const os = require('os');
const path = require('path');

const ПРОЕКТ = path.join(__dirname, '..');
const ФАЙЛ_ПО_УМОЛЧАНИЮ = path.join(ПРОЕКТ, 'игры', 'монополия', 'монополия-экран.js');

const АРГУМЕНТЫ = process.argv.slice(2);
const ЛОМАТЬ = АРГУМЕНТЫ.indexOf('--сломать') !== -1;
const АРГ_ПУТЬ = АРГУМЕНТЫ.find((a) => !a.startsWith('--'));

let проверок = 0;
let провалов = 0;
function проверить(условие, слова) {
  проверок++;
  console.log((условие ? '  ок   — ' : '  ПЛОХО— ') + слова);
  if (!условие) провалов++;
  return условие;
}

/* Ищет в тексте файла экрана кнопку «Построить» (по началу строки
   "Построить " + …, которую button() получает первым доводом) и
   условие if, которое стоит непосредственно перед вызовом button(...).
   Возвращает { найденоКнопок, охрана } — охрана содержит найденный
   текст условия if или null, если его не нашлось вовсе. */
function разобрать(текст) {
  const метка = /"Построить\s"/g;
  const позиции = [];
  let м;
  while ((м = метка.exec(текст)) !== null) позиции.push(м.index);

  if (позиции.length === 0) {
    return { найденоКнопок: 0, охрана: null };
  }

  // Берём первое найденное вхождение (в текущем экране кнопка одна) и
  // смотрим кусок текста перед ним — там должен стоять if(...), сразу
  // за которым (не считая пробелов/переносов/body.append(button() до
  // самого текста кнопки) — никакого другого if быть не должно, иначе
  // это условие относится к чему-то другому.
  const хвост = текст.slice(Math.max(0, позиции[0] - 400), позиции[0]);

  // Последнее вхождение "if (" в хвосте — то, что непосредственно
  // управляет этой кнопкой.
  const ifМетка = /if\s*\(/g;
  let последнийIf = null;
  let совпадение;
  while ((совпадение = ifМетка.exec(хвост)) !== null) последнийIf = совпадение.index;

  if (последнийIf === null) {
    return { найденоКнопок: позиции.length, охрана: null };
  }

  const условие = хвост.slice(последнийIf);
  return { найденоКнопок: позиции.length, охрана: условие };
}

const УСЛОВИЕ_ПОЛНОЕ = /if\s*\(\s*P\.buildable\(\s*v\s*,\s*v\.me\s*,\s*id\s*\)\s*&&\s*!\(\s*v\.auction\s*&&\s*v\.auction\.building\s*\)\s*\)/;

function проверитьФайл(путь) {
  console.log('Файл для проверки: ' + путь);
  const текст = fs.readFileSync(путь, 'utf8');

  const { найденоКнопок, охрана } = разобрать(текст);

  if (!проверить(найденоКнопок > 0, 'в файле нашлась кнопка «Построить» (button("Построить " + …))')) {
    проверить(false, 'условие-охрана перед кнопкой «Построить» не проверить — саму кнопку не нашли');
    return;
  }

  проверить(найденоКнопок === 1, 'кнопка «Построить» встречается в файле ровно один раз (нашлось: ' + найденоКнопок + ')');

  if (!проверить(охрана !== null, 'перед кнопкой «Построить» есть условие if (иначе кнопка рисуется всегда)')) {
    return;
  }

  проверить(
    /P\.buildable\(\s*v\s*,\s*v\.me\s*,\s*id\s*\)/.test(охрана),
    'условие проверяет P.buildable(v, v.me, id) — стройка вообще разрешена правилами',
  );

  проверить(
    /!\(\s*v\.auction\s*&&\s*v\.auction\.building\s*\)/.test(охрана),
    'условие содержит !(v.auction && v.auction.building) — отрицание идущего аукциона за здание',
  );

  проверить(
    УСЛОВИЕ_ПОЛНОЕ.test(охрана),
    'оба требования стоят в ОДНОМ if через && — buildable разрешает, но аукцион за здание перекрывает',
  );
}

/* Убирает из условия перед кнопкой «Построить» кусок про аукцион за
   здание — возвращает старое (дырявое) поведение: кнопка рисуется,
   пока правила разрешают стройку, даже если идёт аукцион за здание. */
function испортить(файл) {
  const текст = fs.readFileSync(файл, 'utf8');
  const приёмПорчи = /P\.buildable\(\s*v,\s*v\.me,\s*id\s*\)\s*&&\s*\n?\s*!\(v\.auction\s*&&\s*v\.auction\.building\)\s*\n?\s*\)/;
  const совпадения = текст.match(new RegExp(приёмПорчи.source, 'g'));
  if (!совпадения || совпадения.length !== 1) {
    throw new Error(
      'приём порчи устарел: ожидалось ровно одно вхождение условия «P.buildable(...) && !(v.auction && v.auction.building))», нашлось ' +
        (совпадения ? совпадения.length : 0),
    );
  }
  const испорченныйТекст = текст.replace(приёмПорчи, 'P.buildable(v, v.me, id))');
  fs.writeFileSync(файл, испорченныйТекст, 'utf8');
}

function сделатьКопиюДляЛомания() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'монополия-построить-в-аукционе-'));
  const копия = path.join(папка, 'монополия-экран.js');
  fs.copyFileSync(ФАЙЛ_ПО_УМОЛЧАНИЮ, копия);
  испортить(копия);
  return копия;
}

if (ЛОМАТЬ) {
  const копия = сделатьКопиюДляЛомания();
  console.log('Ломающий прогон: копия испорчена в ' + копия);
  проверитьФайл(копия);
} else if (АРГ_ПУТЬ) {
  проверитьФайл(path.resolve(АРГ_ПУТЬ));
} else {
  проверитьФайл(ФАЙЛ_ПО_УМОЛЧАНИЮ);
}

console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
process.exit(провалов ? 1 : 0);
