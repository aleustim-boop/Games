/* ---------- поддельный DOM ---------- */

function создатьДокумент() {
  const реестр = new Map();
  const все = [];

  function элемент(тег) {
    const классы = new Set();
    const слушатели = {};
    let _id = '';
    let _текст = '';
    const эл = {
      tagName: тег,
      children: [],
      parentElement: null,
      dataset: {},
      style: { setProperty: function () {}, removeProperty: function () {}, getPropertyValue: function () { return ''; } },
      disabled: false,
      hidden: false,
      classList: {
        add: function () { for (const c of arguments) классы.add(c); },
        remove: function () { for (const c of arguments) классы.delete(c); },
        contains: function (c) { return классы.has(c); },
        toggle: function (c, сила) {
          const нужно = сила === undefined ? !классы.has(c) : Boolean(сила);
          if (нужно) классы.add(c); else классы.delete(c);
          return нужно;
        }
      },
      setAttribute: function () {},
      getAttribute: function () { return null; },
      removeAttribute: function () {},
      addEventListener: function (тип, fn) { (слушатели[тип] = слушатели[тип] || []).push(fn); },
      click: function () { эл.излучить('click', {}); },
      излучить: function (тип, детали) {
        const событие = Object.assign({ target: эл, stopPropagation: function () {}, preventDefault: function () {} }, детали);
        (слушатели[тип] || []).forEach(function (fn) { fn(событие); });
      },
      appendChild: function (реб) { return вставить(эл, реб, null); },
      insertBefore: function (реб, перед) { return вставить(эл, реб, перед); },
      removeChild: function (реб) {
        const и = эл.children.indexOf(реб);
        if (и !== -1) эл.children.splice(и, 1);
        реб.parentElement = null;
        return реб;
      },
      querySelector: function () { return null; },
      querySelectorAll: function () { return []; },
      closest: function (селектор) {
        const класс = селектор.replace(/^\./, '');
        let узел = эл;
        while (узел) {
          if (узел.classList.contains(класс)) return узел;
          узел = узел.parentElement;
        }
        return null;
      },
      getBoundingClientRect: function () { return { left: 0, top: 0, width: 10, height: 10 }; },
      focus: function () {},
      contains: function () { return false; }
    };
    Object.defineProperty(эл, 'parentNode', { get: function () { return эл.parentElement; } });
    Object.defineProperty(эл, 'firstChild', { get: function () { return эл.children[0] || null; } });
    Object.defineProperty(эл, 'nextSibling', {
      get: function () {
        if (!эл.parentElement) return null;
        const братья = эл.parentElement.children;
        return братья[братья.indexOf(эл) + 1] || null;
      }
    });
    Object.defineProperty(эл, 'textContent', {
      get: function () { return _текст; },
      set: function (значение) {
        _текст = String(значение);
        эл.children.forEach(function (реб) { реб.parentElement = null; });
        эл.children.length = 0;
      }
    });
    Object.defineProperty(эл, 'id', {
      get: function () { return _id; },
      set: function (значение) { _id = значение; реестр.set(значение, эл); }
    });
    Object.defineProperty(эл, 'className', {
      get: function () { return Array.from(классы).join(' '); },
      set: function (значение) {
        классы.clear();
        String(значение).split(/\s+/).filter(Boolean).forEach(function (c) { классы.add(c); });
      }
    });
    все.push(эл);
    return эл;
  }

  function вставить(родитель, реб, перед) {
    if (реб.parentElement) реб.parentElement.removeChild(реб);
    const и = перед ? родитель.children.indexOf(перед) : -1;
    if (и === -1) родитель.children.push(реб); else родитель.children.splice(и, 0, реб);
    реб.parentElement = родитель;
    return реб;
  }

  /* Узлы страницы — из настоящего нарды.html: id и классы как в разметке. */
  const запас = элемент('div');
  const теги = html.match(/<(?:section|div|button|span|p|h1|h2|h3|a|img|label|input|select)\b[^>]*\sid="[^"]+"[^>]*>/g) || [];
  for (const тег of теги) {
    const ид = /\sid="([^"]+)"/.exec(тег)[1];
    const кл = /\sclass="([^"]*)"/.exec(тег);
    const эл = элемент('div');
    эл.id = ид;
    if (кл) эл.className = кл[1];
    эл.parentElement = запас;
  }
  const документ = {
    readyState: 'complete',
    body: запас,
    documentElement: элемент('html'),
    createElement: function (тег) { return элемент(тег); },
    getElementById: function (ид) { return реестр.has(ид) ? реестр.get(ид) : null; },
    querySelectorAll: function (селектор) {
      const класс = селектор.replace(/^\./, '');
      return все.filter(function (э) { return э.classList.contains(класс); });
    },
    querySelector: function (селектор) {
      const классы = селектор.split('.').filter(Boolean);
      return все.find(function (э) { return классы.every(function (к) { return э.classList.contains(к); }); }) || null;
    },
    addEventListener: function () {}
  };
  return { документ: документ, все: все, реестр: реестр };
}

/* ---------- одна «страница»: песочница с хранилищем ---------- */

function создатьХранилище(начальное) {
  const данные = new Map(Object.entries(начальное || {}));
  return {
    данные: данные,
    ломается: false,
    getItem: function (к) { if (this.ломается) throw new Error('память закрыта'); return данные.has(к) ? данные.get(к) : null; },
    setItem: function (к, з) { if (this.ломается) throw new Error('память закрыта'); данные.set(к, String(з)); },
    removeItem: function (к) { if (this.ломается) throw new Error('память закрыта'); данные.delete(к); }
  };
}

function открытьСтраницу(хранилище, путьЭкрана, адрес) {
  const { документ, все, реестр } = создатьДокумент();
  const очередь = [];
  let время = 0;
  const слушателиОкна = {};
  let последняяОшибка = null;
  const окно = {
    document: документ,
    localStorage: хранилище,
    location: { search: адрес || '', href: '' },
    console: { log: function () {}, warn: function () {}, error: function (...а) { последняяОшибка = а.join(' '); } },
    matchMedia: function () { return { matches: true }; },   // «меньше движения»: кубики и шашки без анимации
    addEventListener: function (тип, fn) { (слушателиОкна[тип] = слушателиОкна[тип] || []).push(fn); },
    dispatchEvent: function (событие) { (слушателиОкна[событие.type] || []).forEach(function (fn) { fn(событие); }); },
    setTimeout: function (fn, мс) { очередь.push({ fn: fn, когда: время + (мс || 0), номер: очередь.length }); return очередь.length; },
    clearTimeout: function () {},
    setInterval: function () { return 0; },
    clearInterval: function () {},
    CustomEvent: function (тип) { this.type = тип; },
    Date: Date, JSON: JSON, Object: Object, Array: Array, Number: Number, String: String, Boolean: Boolean,
    URLSearchParams: URLSearchParams, Map: Map, Set: Set, Promise: Promise, Error: Error, parseInt: parseInt, isFinite: isFinite
  };
  окно.window = окно;
  const песочница = vm.createContext(окно);
  // Свой Math со своим «случайным»: прогон повторяется слово в слово.
  let зерно = 12345;
  const математика = Object.create(Math);
  математика.random = function () { зерно = (зерно * 1103515245 + 12345) % 2147483648; return зерно / 2147483648; };
  окно.Math = математика;

  function запустить(код, имя) {
    vm.runInContext('(function () {\n' + код + '\n}).call(this);', песочница, { filename: имя });
  }
  запустить(исходники.правила, 'нарды-правила.js');
  запустить(исходники.бот, 'нарды-бот.js');
  запустить(исходники.лобби, 'нарды-лобби.js');
  запустить(fs.readFileSync(путьЭкрана, 'utf8'), 'нарды-экран.js');

  const страница = {
    окно: окно,
    узел: function (ид) { return документ.getElementById(ид); },
    ошибка: function () { return последняяОшибка; },
    /** Выполнить все отложенные дела (таймеры бота и пауз). */
    прокрутить: function (предел) {
      let шагов = 0;
      while (очередь.length && шагов++ < (предел || 5000)) {
        очередь.sort(function (а, б) { return а.когда - б.когда || а.номер - б.номер; });
        const дело = очередь.shift();
        время = Math.max(время, дело.когда);
        дело.fn();
      }
    },
    /** Выполнить только первое отложенное дело — чтобы застать бота посреди хода. */
    одноДело: function () {
      очередь.sort(function (а, б) { return а.когда - б.когда || а.номер - б.номер; });
      const дело = очередь.shift();
      if (!дело) return false;
      время = Math.max(время, дело.когда);
      дело.fn();
      return true;
    },
    нажать: function (ид) {
      const эл = документ.getElementById(ид);
      if (!эл) throw new Error('нет узла «' + ид + '»');
      эл.click();
    },
    /** Нажать пункт, бар или полку так, как нажимает палец. */
    тапМесто: function (место) {
      let цель = null;
      if (место === 'вне') {
        цель = все.find(function (э) { return э.classList.contains('полка') && !э.classList.contains('полка--чёрные') === (страница.чейХодСейчас() === 'белые'); });
        if (!цель) throw new Error('нет полки');
        цель.click();
        return;
      }
      if (место === 'бар') {
        цель = все.find(function (э) { return э.classList.contains('бар__половина') && э.dataset.бар === страница.чейХодСейчас(); });
      } else {
        цель = все.find(function (э) { return э.classList.contains('пункт') && э.dataset.пункт === String(место); });
      }
      if (!цель) throw new Error('нет места ' + место);
      документ.getElementById('доска').излучить('click', { target: цель });
    },
    чейХодСейчас: function () { const з = запись(хранилище); return з ? з.партия.ходит : null; },
    кубикиНаСтоле: function () {
      return документ.getElementById('кубики').children.map(function (к) { return Number(к.dataset.очки); });
    },
    скрыто: function (ид) { return документ.getElementById(ид).classList.contains('скрыт'); },
    виден: function (ид) { return документ.getElementById(ид).classList.contains('экран--виден'); },
    закрытие: function () { окно.dispatchEvent(new окно.CustomEvent('перед-закрытием')); }
  };
  return страница;
}

/** Запись из хранилища разобранная или null. */
function запись(хранилище) {
  const текст = хранилище.данные.get(КЛЮЧ);
  return текст === undefined ? null : JSON.parse(текст);
}

/** Запись без отметки времени — для сравнения «до» и «после». */
function безОтметки(з) {
  if (!з) return null;
  const копия = Object.assign({}, з);
  delete копия.отметка;
  return JSON.stringify(копия);
}

/* ---------- сами проверки ---------- */

function прогнать(путьЭкрана) {
  let провалов = 0;
  let всего = 0;
  const тихо = process.argv.includes('--тихо');
  function проверить(условие, слова) {
    всего++;
    if (!условие) провалов++;
    if (!тихо) console.log((условие ? '  ок      ' : '  ПРОВАЛ  ') + слова);
  }
  function безПадения(слова, дело) {
    try { return дело(); } catch (ошибка) {
      проверить(false, слова + ' — упало: ' + ошибка.message);
      return undefined;
    }
  }

  /** Один свой ход человека: найти законное перемещение и сделать тапами. */
  function шагЧеловека(страница, хранилище) {
    const з = запись(хранилище);
    const партия = Правила.партияИзКартинки(з.партия);
    const шаги = Правила.возможныеШаги(партия);
    if (!шаги.length) return false;
    const шаг = шаги[0];
    страница.тапМесто(шаг.откуда);
    страница.тапМесто(шаг.куда);
    return true;
  }

  /** Сыграть человеком целый ход (бросок, все шаги, подтверждение) и дать боту ответить. */
  function круг(страница, хранилище) {
    страница.нажать('кнопка-бросить');
    страница.прокрутить();
    let защита = 10;
    while (защита-- > 0 && страница.скрыто('кнопка-закончить-ход')) {
      if (!шагЧеловека(страница, хранилище)) break;
      страница.прокрутить();
    }
    страница.нажать('кнопка-закончить-ход');
  }

  console.log('Экран: ' + путьЭкрана);

  /* ---- 1. запись при игре с ботом ---- */
  console.log('\n1. Партия с ботом пишется после каждого изменения');
  const память = создатьХранилище();
  const стр = открытьСтраницу(память, путьЭкрана);
  проверить(стр.ошибка() === null, 'страница открылась без ошибок в консоли');
  проверить(стр.виден('экран-лобби'), 'открывается лобби');
  проверить(!!стр.узел('кнопка-доиграть-с-ботом') && стр.скрыто('кнопка-доиграть-с-ботом'), 'плашка «доиграть» есть и спрятана, пока записи нет');
  проверить(!память.данные.has(КЛЮЧ), 'записи до партии нет');

  безПадения('начало партии', function () {
    стр.нажать('уровень-лёгкий');
    стр.нажать('кнопка-с-ботом');
  });
  const начальная = запись(память);
  проверить(!!начальная && начальная.в === 1 && начальная.режим === 'бот', 'начало партии — запись есть (вид 1, режим «бот»)');
  проверить(!!начальная && начальная.уровень === 'лёгкий', 'в записи уровень бота');

  безПадения('бросок', function () { стр.нажать('кнопка-бросить'); стр.прокрутить(); });
  const послеБроска = запись(память);
  проверить(!!послеБроска && Array.isArray(послеБроска.партия.бросок) && послеБроска.партия.бросок.length === 2,
    'после броска в записи те же кубики, что выпали');
  проверить(!!послеБроска && стр.кубикиНаСтоле().length >= 2 &&
    стр.кубикиНаСтоле()[0] === послеБроска.партия.бросок[0],
    'кубики на столе показаны и совпадают с записанными');

  безПадения('ход', function () {
    let сыграли = 0;
    const было = послеБроска.партия.сыграно.length;
    if (шагЧеловека(стр, память)) { стр.прокрутить(); сыграли = 1; }
    const после = запись(память);
    проверить(сыграли === 1 && !!после && после.партия.сыграно.length === было + 1, 'после своего перемещения запись новая (шашка сыграна)');
  });

  /* Играем несколько кругов с ботом: после каждого записана позиция. */
  безПадения('круги с ботом', function () {
    for (let i = 0; i < 4; i++) {
      const было = безОтметки(запись(память));
      круг(стр, память);
      стр.прокрутить();
      const стало = запись(память);
      проверить(!!стало && безОтметки(стало) !== было, 'круг ' + (i + 1) + ': запись обновилась после своего хода и хода бота');
      if (!стало) break;
      проверить(стало.партия.ходит === 'белые' && стало.партия.бросок === null,
        'круг ' + (i + 1) + ': после ответа бота записан ход человека без брошенных кубиков');
    }
  });

  /* ---- 2. «перезагрузка» ---- */
  console.log('\n2. «Перезагрузка»: та же доска, чей ход, те же кости');
  безПадения('бросок и один ход перед закрытием', function () {
    стр.нажать('кнопка-бросить');
    стр.прокрутить();
    шагЧеловека(стр, память);
    стр.прокрутить();
  });
  const доЗакрытия = запись(память);
  проверить(!!доЗакрытия && Array.isArray(доЗакрытия.партия.бросок), 'перед закрытием: бросок сделан, ход начат');
  const кубикиДо = стр.кубикиНаСтоле();

  const стр2 = открытьСтраницу(память, путьЭкрана);
  проверить(стр2.ошибка() === null, 'новая страница открылась без ошибок');
  проверить(стр2.виден('экран-лобби') && !стр2.скрыто('кнопка-доиграть-с-ботом'), 'в лобби видна плашка «доиграть»');
  проверить(/с ботом/.test(стр2.узел('кнопка-доиграть-с-ботом').textContent), 'плашка говорит «с ботом»');
  безПадения('возврат', function () { стр2.нажать('кнопка-доиграть-с-ботом'); });
  проверить(стр2.виден('экран-игры'), 'по нажатию открывается стол');
  const послеВозврата = запись(память);
  проверить(безОтметки(доЗакрытия) === безОтметки(послеВозврата), 'доска, чей ход, кубики и ход — в точности те же');
  проверить(JSON.stringify(стр2.кубикиНаСтоле()) === JSON.stringify(кубикиДо) && кубикиДо.length >= 2,
    'на столе те же кубики (' + кубикиДо.join(',') + '), не переброшены');
  проверить(стр2.скрыто('кнопка-бросить'), 'кнопка «Бросить» спрятана — повторно бросать нельзя');
  безПадения('доигрывание', function () {
    круг(стр2, память);
    стр2.прокрутить();
    const з = запись(память);
    проверить(!!з && з.партия.ходит === 'белые' && з.партия.бросок === null, 'партия идёт дальше: ход доигран, бот сходил');
  });

  /* Запись с начала хода бота: после возврата бот ходит сам. */
  безПадения('возврат в ход бота', function () {
    const п = открытьСтраницу(память, путьЭкрана);
    п.нажать('кнопка-доиграть-с-ботом');
    п.нажать('кнопка-бросить');
    п.прокрутить();
    while (п.скрыто('кнопка-закончить-ход') && шагЧеловека(п, память)) п.прокрутить();
    п.нажать('кнопка-закончить-ход');
    // сразу после подтверждения — запись «чёрные ходят», бот ещё не брался
    проверить(запись(память).партия.ходит === 'чёрные' && запись(память).партия.бросок === null,
      'после подтверждения хода записано: ходят чёрные, кубиков нет');
    const р = открытьСтраницу(память, путьЭкрана);
    р.нажать('кнопка-доиграть-с-ботом');
    р.прокрутить();
    проверить(запись(память).партия.ходит === 'белые', 'вернулись в ход бота — он сходил сам и передал ход');
  });

  /* ---- 3. вдвоём на одном устройстве ---- */
  console.log('\n3. «Вдвоём на этом устройстве»');
  безПадения('вдвоём', function () {
    const п = создатьХранилище();
    const а = открытьСтраницу(п, путьЭкрана);
    а.нажать('кнопка-вдвоём');
    а.нажать('кнопка-бросить');
    а.прокрутить();
    const з = запись(п);
    проверить(!!з && з.режим === 'вдвоём', 'запись режима «вдвоём»');
    const б = открытьСтраницу(п, путьЭкрана);
    проверить(!б.скрыто('кнопка-доиграть-с-ботом') && /вдвоём/.test(б.узел('кнопка-доиграть-с-ботом').textContent), 'плашка говорит «вдвоём»');
    б.нажать('кнопка-доиграть-с-ботом');
    проверить(безОтметки(з) === безОтметки(запись(п)), 'вдвоём: та же доска и те же кубики');
  });

  /* ---- 4. конец партии и выход по своей воле ---- */
  console.log('\n4. Конец партии и выход стирают запись');
  безПадения('конец партии', function () {
    // Позиция перед последним выносом: у белых одна шашка на 3, остальные вынесены.
    const партия = Правила.партияИзРасстановки('короткие', {
      ходит: 'белые', ходов: { белые: 9, чёрные: 9 },
      белые: { 3: 1 }, чёрные: { 24: 15 }
    });
    Правила.бросить(партия, [6, 5]);
    const п = создатьХранилище({
      [КЛЮЧ]: JSON.stringify({ в: 1, отметка: 1, режим: 'вдвоём', уровень: 'сложный', партия: Правила.картинкаПартии(партия) })
    });
    const а = открытьСтраницу(п, путьЭкрана);
    а.нажать('кнопка-доиграть-с-ботом');
    проверить(п.данные.has(КЛЮЧ), 'перед последним ходом запись жива');
    а.тапМесто(3);
    а.тапМесто('вне');
    а.прокрутить();
    проверить(!п.данные.has(КЛЮЧ), 'партия выиграна — записи нет');
    const б = открытьСтраницу(п, путьЭкрана);
    проверить(б.скрыто('кнопка-доиграть-с-ботом'), 'после конца плашки «доиграть» нет');
  });

  безПадения('выход по своей воле', function () {
    const п = создатьХранилище();
    const а = открытьСтраницу(п, путьЭкрана);
    а.нажать('кнопка-с-ботом');
    а.нажать('кнопка-бросить');
    а.прокрутить();
    проверить(п.данные.has(КЛЮЧ), 'перед выходом запись есть');
    а.нажать('кнопка-в-меню');
    проверить(!п.данные.has(КЛЮЧ), '«В меню» по своей воле — записи нет');
    проверить(а.виден('экран-лобби') && а.скрыто('кнопка-доиграть-с-ботом'), 'в лобби плашки «доиграть» нет');
  });

  безПадения('новая партия поверх', function () {
    const п = создатьХранилище();
    const а = открытьСтраницу(п, путьЭкрана);
    а.нажать('кнопка-с-ботом');
    а.нажать('кнопка-бросить');
    а.прокрутить();
    а.нажать('кнопка-вдвоём');
    const з = запись(п);
    проверить(!!з && з.режим === 'вдвоём' && з.партия.бросок === null, '«новая партия» заменила запись чистой');
  });

  /* ---- 5. мусор ---- */
  console.log('\n5. Мусор в памяти не роняет страницу');
  const годная = JSON.parse(память.данные.get(КЛЮЧ) || 'null');
  const мусор = {
    'пустая строка': '',
    'обрезанный текст': '{"в":1,"реж',
    'не объект': '42',
    'массив': '[]',
    'null': 'null',
    'чужой вид записи': JSON.stringify(Object.assign({}, годная, { в: 99 })),
    'чужой режим': JSON.stringify(Object.assign({}, годная, { режим: 'сеть' })),
    'чужой уровень': JSON.stringify(Object.assign({}, годная, { уровень: 'бог' })),
    'нет партии': JSON.stringify(Object.assign({}, годная, { партия: null })),
    'кубики 7': JSON.stringify(Object.assign({}, годная, { партия: Object.assign({}, годная && годная.партия, { бросок: [7, 1] }) })),
    'пропала шашка': (function () {
      const к = JSON.parse(JSON.stringify(годная));
      for (let п = 1; п <= 24; п++) if (к.партия.пункты[п].length) { к.партия.пункты[п].pop(); break; }
      return JSON.stringify(к);
    })(),
    'в стопке не массив': (function () {
      const к = JSON.parse(JSON.stringify(годная));
      к.партия.пункты[5] = 'х';
      return JSON.stringify(к);
    })(),
    'партия уже закончена': JSON.stringify(Object.assign({}, годная, { партия: Object.assign({}, годная && годная.партия, { завершена: true }) }))
  };
  проверить(!!годная, 'образец годной записи для порчи есть');
  for (const имя of Object.keys(мусор)) {
    безПадения('мусор «' + имя + '»', function () {
      const п = создатьХранилище({ [КЛЮЧ]: мусор[имя] });
      const а = открытьСтраницу(п, путьЭкрана);
      проверить(а.ошибка() === null && а.скрыто('кнопка-доиграть-с-ботом') && !п.данные.has(КЛЮЧ),
        'мусор «' + имя + '»: страница цела, плашки нет, запись стёрта');
    });
  }
  безПадения('память закрыта', function () {
    const п = создатьХранилище();
    п.ломается = true;
    const а = открытьСтраницу(п, путьЭкрана);
    а.нажать('кнопка-с-ботом');
    а.нажать('кнопка-бросить');
    а.прокрутить();
    а.закрытие();
    проверить(а.ошибка() === null && а.виден('экран-игры'), 'память с ошибками: игра идёт без падений');
  });

  /* ---- 6. перед закрытием ---- */
  console.log('\n6. Событие «перед-закрытием» и ход бота');
  безПадения('перед закрытием', function () {
    const п = создатьХранилище();
    const а = открытьСтраницу(п, путьЭкрана);
    а.нажать('кнопка-с-ботом');
    а.нажать('кнопка-бросить');
    а.прокрутить();
    const ожидаемое = безОтметки(запись(п));
    п.данные.delete(КЛЮЧ);
    а.закрытие();
    проверить(безОтметки(запись(п)) === ожидаемое && !!ожидаемое, 'после «перед-закрытием» запись снова на месте и та же');
  });
  безПадения('посреди хода бота', function () {
    const п = создатьХранилище();
    const а = открытьСтраницу(п, путьЭкрана);
    а.нажать('уровень-лёгкий');
    а.нажать('кнопка-с-ботом');
    а.нажать('кнопка-бросить');
    а.прокрутить();
    let защита = 10;
    while (защита-- > 0 && а.скрыто('кнопка-закончить-ход')) { if (!шагЧеловека(а, п)) break; а.прокрутить(); }
    а.нажать('кнопка-закончить-ход');
    const началоХодаБота = безОтметки(запись(п));
    проверить(запись(п).партия.ходит === 'чёрные', 'ход передан боту, запись — начало его хода');
    а.одноДело();                     // бот бросил кубики и начал ходить
    а.закрытие();                     // закрыли посреди его хода
    проверить(безОтметки(запись(п)) === началоХодаБота, 'посреди хода бота запись не портится: остаётся начало хода');
  });

  /* ---- 7. витрина просит «сразу» ---- */
  console.log('\n7. «Начать сразу» с витрины не затирает сохранённую партию');
  безПадения('сразу', function () {
    const п = создатьХранилище();
    const а = открытьСтраницу(п, путьЭкрана);
    а.нажать('кнопка-с-ботом');
    а.нажать('кнопка-бросить');
    а.прокрутить();
    const было = безОтметки(запись(п));
    const б = открытьСтраницу(п, путьЭкрана, '?сразу=1');
    проверить(б.виден('экран-игры') && безОтметки(запись(п)) === было, 'вернулись в сохранённую партию, а не в новую');
  });

  console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
  return провалов;
}

