    try {
      process.argv.push('--тихо');
      провалов = прогнать(копия);
    } catch (ошибка) {
      провалов = 1;   // проверка упала целиком — тоже «покраснела»
    } finally {
      process.argv.pop();
    }
    console.log((провалов > 0 ? 'покраснела  ' : 'НЕ ПОКРАСНЕЛА  ') + ломка.имя + ' (провалов: ' + провалов + ')');
