'use strict';

/* =====================================================================
   Собрать стол по сети и играть за одно из мест.

   Зачем понадобился. Проверять справедливость очереди надо не только
   в игре с ботами на своей странице, но и по сети: правила там считает
   сервер. А жалоба живого игрока была про ЧЕТВЁРТОЕ место — значит,
   проверяющему надо сесть четвёртым, то есть войти в комнату последним.
   Кто-то должен создать её раньше и нажать «Начать» позже. Этот кто-то
   и есть здешний помощник.

   Что делает:
     • создаёт комнату с заданным столом (мест, парами, переводной);
     • печатает код — его набирают в браузере;
     • ждёт, пока все места займут; свободные, если ждать надоело,
       занимает ботами;
     • нажимает «Начать» и дальше играет за своё место сам;
     • после партии соглашается на новую.

   Как запускать (сервер комнат уже поднят):

       node tests/стол-по-сети.js 8790 мест 4 парами
       node tests/стол-по-сети.js 8790 мест 4 парами ждать 60 имя Первый

   «ждать N» — сколько секунд ждать живых игроков, прежде чем посадить
   ботов на свободные места (по умолчанию 90).
   ===================================================================== */

const http = require('http');

function довод(имя, поумолчанию) {
  const где = process.argv.indexOf(имя);
  if (где === -1) return поумолчанию;
  const з = process.argv[где + 1];
  return з === undefined ? поумолчанию : з;
}

const ПОРТ = Number(process.argv[2]) || 8790;
const МЕСТ = Number(довод('мест', 4)) || 4;
const ПАРАМИ = process.argv.indexOf('парами') !== -1;
const ПЕРЕВОДНОЙ = process.argv.indexOf('переводной') !== -1;
const ЖДАТЬ = Math.round(Number(довод('ждать', 90)) * 1000);
const МОЁ_ИМЯ = довод('имя', 'Первый');
const ХОЗЯИН = '127.0.0.1';

function спросить(путь, тело) {
  return new Promise((готово, беда) => {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, (ответ) => {
      let текст = '';
      ответ.setEncoding('utf8');
      ответ.on('data', (к) => { текст += к; });
      ответ.on('end', () => {
        let р = null;
        try { р = JSON.parse(текст); } catch (сбой) { р = { сырое: текст }; }
        готово({ код: ответ.statusCode, тело: р });
      });
    });
    запрос.setTimeout(40000, () => запрос.destroy(new Error('сервер молчит')));
    запрос.on('error', беда);
    запрос.end(данные);
  });
}

const пауза = (мс) => new Promise((r) => setTimeout(r, мс));
const час = () => new Date().toTimeString().slice(0, 8);

let подкидыватьБольшеНеПробуем = false;

function бьёт(чем, что, козырь) {
  if (чем.масть === что.масть) return чем.вес > что.вес;
  return чем.масть === козырь && что.масть !== козырь;
}

/** Самый простой игрок: кроет мелкой, ходит с мелочи. Взято из подсадить-игрока.js. */
function решить(вид) {
  const рука = вид.мояРука || [];
  const стол = вид.стол || [];
  const козырь = вид.козырь;
  const яЗащищаюсь = вид.яОтбиваюсь === undefined
    ? (вид.фаза === 'защита' && вид.яХожу)
    : вид.яОтбиваюсь;

  if (яЗащищаюсь && !вид.берут) {
    let номер = -1;
    for (let i = 0; i < стол.length; i++) { if (!стол[i].защита) { номер = i; break; } }
    if (номер < 0) return null;
    const атака = стол[номер].атака;
    const годные = рука.map((к, i) => ({ к, i }))
      .filter((п) => атака && бьёт(п.к, атака, козырь))
      .sort((а, б) => (а.к.масть === козырь ? 1 : 0) - (б.к.масть === козырь ? 1 : 0) || а.к.вес - б.к.вес);
    if (годные.length) return { действие: 'отбить', пара: номер, карта: годные[0].i };
    return { действие: 'беру' };
  }

  if (вид.яХожу) {
    if (!рука.length) return стол.length ? { действие: 'бито' } : null;
    if (!стол.length) {
      const порядок = рука.map((к, i) => ({ к, i }))
        .sort((а, б) => (а.к.масть === козырь ? 1 : 0) - (б.к.масть === козырь ? 1 : 0) || а.к.вес - б.к.вес);
      return { действие: 'ходить', карта: порядок[0].i };
    }
    if (подкидыватьБольшеНеПробуем) return { действие: 'бито' };
    const веса = new Set();
    стол.forEach((п) => { if (п.атака) веса.add(п.атака.вес); if (п.защита) веса.add(п.защита.вес); });
    const годная = рука.findIndex((к) => веса.has(к.вес) && к.масть !== козырь);
    if (годная >= 0) return { действие: 'ходить', карта: годная };
    return { действие: 'бито' };
  }
  return null;
}

/* Сколько мест за столом уже заняты. Сервер присылает в «застолом»
   ТОЛЬКО занятые места (см. «списокМест» в server/комнаты.js), поэтому
   считать нечего — достаточно длины списка. */
function занято(вид) {
  return (вид && вид.застолом ? вид.застолом : []).length;
}

async function главная() {
  const настройки = { имя: МОЁ_ИМЯ, мест: МЕСТ };
  if (ПАРАМИ) настройки.парами = true;
  if (ПЕРЕВОДНОЙ) настройки.переводной = true;

  const создано = await спросить('/создать', настройки);
  if (создано.код !== 200) {
    console.error('не дали создать комнату: ' + JSON.stringify(создано.тело));
    process.exit(1);
  }
  const код = создано.тело.код;
  const пропуск = создано.тело.пропуск;
  console.log(час() + ' КОД КОМНАТЫ: ' + код + '  (мест ' + МЕСТ + (ПАРАМИ ? ', парами' : '') + ')');
  console.log(час() + ' жду живых игроков ' + (ЖДАТЬ / 1000) + ' с, потом посажу ботов');

  // 1. Ждём, пока стол наполнится
  const началоОжидания = Date.now();
  for (;;) {
    const с = await спросить('/состояние', { код, пропуск });
    const вид = (с.тело && (с.тело.состояние || с.тело)) || {};
    const сколько = занято(вид);
    if (сколько >= МЕСТ) { console.log(час() + ' стол полон'); break; }
    if (Date.now() - началоОжидания > ЖДАТЬ) {
      console.log(час() + ' ждать надоело, занято ' + сколько + ' из ' + МЕСТ + ' — сажаю ботов');
      for (let i = сколько; i < МЕСТ; i++) await спросить('/ход', { код, пропуск, действие: 'бот' });
      break;
    }
    await пауза(1000);
  }

  // 2. Начинаем
  const пуск = await спросить('/ход', { код, пропуск, действие: 'начать' });
  console.log(час() + ' «Начать»: ' + JSON.stringify(пуск.тело && пуск.тело.принято !== false ? 'принято' : пуск.тело));

  // 3. Играем
  for (let шаг = 0; шаг < 100000; шаг++) {
    const с = await спросить('/состояние', { код, пропуск });
    if (с.код !== 200) { console.log(час() + ' комната пропала: ' + с.код); break; }
    const вид = с.тело.состояние || с.тело;
    if (вид.завершена) {
      console.log(час() + ' партия окончена, итог для меня: ' + вид.итог);
      await спросить('/ход', { код, пропуск, действие: 'ещё' });
      await пауза(1500);
      continue;
    }
    if (!(вид.стол || []).length) подкидыватьБольшеНеПробуем = false;
    const намерение = решить(вид);
    if (!намерение) { await пауза(300); continue; }
    const о = await спросить('/ход', Object.assign({ код, пропуск }, намерение));
    if (о.тело && о.тело.принято === false) {
      if (намерение.действие === 'ходить') подкидыватьБольшеНеПробуем = true;
      await пауза(500);
    }
    await пауза(250);
  }
}

главная().catch((сбой) => { console.error('Сорвалось: ' + сбой.message); process.exitCode = 1; });
