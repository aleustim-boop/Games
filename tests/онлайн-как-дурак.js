function ломающийЗапуск() {
  console.log('Ломающий запуск --сломать: портим КОПИИ во временной папке.\n');
  let проверок = 0;
  let провалов = 0;
  СЦЕНАРИИ.forEach(function (с) {
    console.log('Сценарий ' + с.имя + ' (' + с.что + '):');
    const результат = с.выполнить();
    const текст = результат.итог.провалы.join('\n');
    результат.ждём.forEach(function (ждём) {
      проверок++;
      const строка = результат.итог.провалы.find(function (п) { return п.indexOf(ждём) !== -1; });
      if (строка) { провалов++; console.log('  ПРОВАЛ: ' + строка); }
      else console.log('  СЛЕПА: нет провала «' + ждём + '»; были: ' + (текст || 'ничего'));
    });
    console.log('');
  });
  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
}

/* ---------------- Запуск ---------------- */

if (process.argv.indexOf('--сломать') !== -1) {
  ломающийЗапуск();
} else {
  const довод = process.argv.find(function (а) { return а.indexOf('--корень=') === 0; });
  const корень = довод ? path.resolve(довод.slice('--корень='.length)) : ПРОЕКТ;
  const итог = проверитьКорень(корень, false);
  console.log('\nИтого проверок: ' + итог.проверок + ', провалов: ' + итог.провалы.length);
  process.exit(итог.провалы.length ? 1 : 0);
}
