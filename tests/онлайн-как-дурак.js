      const без = т.replace(/<script[^>]*\ssrc="js\/подбор-экран\.js[^"]*"[^>]*><\/script>/, '');
      if (без === т) throw new Error('приём порчи устарел: в нарды.html не нашлось подключение js/подбор-экран.js');
