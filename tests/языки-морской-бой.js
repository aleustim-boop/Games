/* Проверка словаря перевода страницы «Морской бой» (чистый node, без браузера).
   Запуск: node tests/языки-морской-бой.js [путь к копии js/языки-морской-бой.js]
   Путь доводом нужен ломающему запуску: он подсовывает испорченную копию
   словаря из временной папки, настоящий файл не трогается. */
const fs = require('fs');
const path = require('path');
const корень = path.join(__dirname, '..');
const путьСловаря = process.argv[2] || path.join(корень, 'js', 'языки-морской-бой.js');

// Откуда берём русские фразы страницы.
const ИСТОЧНИКИ = [ "морской-бой.html", "js/морской-бой-экран.js", "js/морской-бой-флот.js", "js/морской-бой-память.js", "js/морской-бой-правила.js", "server/игры/морской-бой.js" ];

// Что сознательно не переводим: [фраза, причина]. Каждая запись обязана
// встретиться в источниках — иначе она устарела и проверка краснеет.
const НЕ_ПЕРЕВОДИМ = [
  ["[data-назад]", "имя атрибута, не текст"],
  ["[data-меню]", "имя атрибута, не текст"],
  ["[data-уровень]", "имя атрибута, не текст"],
  ["[data-клетка=\"§\"]", "селектор, не текст"],
  ["морской-бой-партия-v1", "ключ памяти телефона"],
  ["АБВГДЕЖЗИК", "буквы-координаты поля: это адреса клеток, а не слова"],
  ["-е место", "кусок склейки; целая фраза «N-е место» есть в общем словаре"]
];

// Фразы, которые игрок видит целиком, а в коде они склеены: обязаны переводиться.
const СБОРКИ = [
  ["0 из 10 кораблей", "0 з 10 кораблів", "0 of 10 ships"],
  ["10 × 10 · 10 кораблей · без касаний", "10 × 10 · 10 кораблів · без дотиків", "10 × 10 · 10 ships · no touching"],
  ["Два игрока · поле 10 × 10 · десять кораблей", "Два гравці · поле 10 × 10 · десять кораблів", "Two players · 10 × 10 board · ten ships"],
  ["Классический · 10 × 10", "Класичний · 10 × 10", "Classic · 10 × 10"],
  ["Цель: Б7", "Ціль: Б7", "Target: Б7"],
  ["Вы · Б7 — ранен", "Ви · Б7 — поранено", "You · Б7 — hit"],
  ["Соперник · Г3 — потоплен", "Суперник · Г3 — потоплено", "Opponent · Г3 — sunk"],
  ["Потоплено 3 / 10", "Потоплено 3 / 10", "Sunk 3 / 10"],
  ["23 выстрелов · точность 41%", "23 пострілів · точність 41%", "23 shots · accuracy 41%"],
  ["3 палубы: осталось 2", "3 палуби: залишилось 2", "3-deck: 2 left"]
];

const кир = /[А-Яа-яЁё]/;
const норм = с => String(с).replace(/\s+/g, ' ').trim();
const служебное = с => /^[.#]?[а-яё0-9_.:§-]+$/.test(с) || /^[.#]/.test(с) || /(--|__)/.test(с) ||
  /^img\//.test(с);   // пути к картинкам и классы — не текст на экране

/* Русские фразы из js: сливаем «'а' + 'б'», выкидываем комментарии,
   подстановки ${…} заменяем на «§». Теги внутри строки режут её на куски. */
function фразыИзJs(код) {
  код = код.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|\s)\/\/[^\n]*/g, '$1');
  код = код.replace(/'\s*\+\s*'/g, '').replace(/"\s*\+\s*"/g, '');
  const найдено = [];
  const re = /'((?:[^'\\\n]|\\.)*)'|"((?:[^"\\\n]|\\.)*)"|`((?:[^`\\]|\\.)*)`/g;
  let м;
  while ((м = re.exec(код))) {
    const с = м[1] ?? м[2] ?? м[3];
    if (!кир.test(с)) continue;
    const чистая = с.replace(/\\n/g, ' ').replace(/\\(['"`])/g, '$1').replace(/\$\{[^}]*\}/g, '§');
    for (const часть of чистая.split(/<[^>]*>/)) {
      const н = норм(часть);
      if (кир.test(н) && !служебное(н)) найдено.push(н);
    }
  }
  return найдено;
}
function фразыИзHtml(текст) {
  const найдено = [];
  текст = текст.replace(/<!--[\s\S]*?-->/g, ' ');
  текст = текст.replace(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g, (_, к) => { найдено.push(...фразыИзJs(к)); return ' '; });
  текст = текст.replace(/<script[^>]*>[\s\S]*?<\/script>/g, ' ').replace(/<style[\s\S]*?<\/style>/g, ' ');
  for (const м of текст.matchAll(/\b(?:aria-label|title|placeholder|alt)="([^"]*)"/g)) if (кир.test(м[1])) найдено.push(норм(м[1]));
  for (const м of текст.matchAll(/>([^<]+)</g)) if (кир.test(м[1])) найдено.push(норм(м[1]));
  return найдено;
}

const ошибки = [];
const провал = текст => ошибки.push(текст);

// Общий словарь грузим первым и запоминаем его ключи; словарь игры — следом.
const Языки = require(path.join(корень, 'js', 'языки.js'));
const ключиОбщего = new Set(Object.keys(Языки.словарь));
const исходныйТекст = fs.readFileSync(путьСловаря, 'utf8');
new Function('require', 'module', 'window', исходныйТекст)(
  п => (п === './языки' ? Языки : require(п)), { exports: {} }, undefined);

// 1. Устройство словаря: три части, без повторов, шаблоны с верными $n.
const блок = /const строки = `([\s\S]*?)`;/.exec(исходныйТекст);
if (!блок) провал('в словаре не найден блок «const строки = `…`»');
const строкиСловаря = блок ? блок[1].split('\n').filter(с => с.trim()) : [];
const видели = new Set();
for (const строка of строкиСловаря) {
  const части = строка.split('|');
  if (части.length !== 3 || части.some(ч => !ч.trim())) { провал('строка без трёх непустых частей: ' + строка.slice(0, 60)); continue; }
  const ключ = норм(части[0]);
  if (видели.has(ключ)) провал('ключ повторяется: ' + ключ.slice(0, 60));
  видели.add(ключ);
  if (ключиОбщего.has(ключ)) провал('ключ уже есть в общем словаре js/языки.js: ' + ключ.slice(0, 60));
}
if (строкиСловаря.length < 80) провал('в словаре подозрительно мало строк: ' + строкиСловаря.length);

const шаблоныВФайле = [...исходныйТекст.matchAll(/^\s*\[\/(.+)\/, '([^']*)', '([^']*)'\],?$/gm)];
if (!шаблоныВФайле.length) провал('в словаре не найдено ни одного шаблона');
for (const [, исходник, uk, en] of шаблоныВФайле) {
  let скобок = 0;
  try { скобок = new RegExp(исходник + '|').exec('').length - 1; } catch (e) { провал('шаблон не разбирается: ' + исходник); continue; }
  for (const перевод of [uk, en]) {
    const номера = [...перевод.matchAll(/\$(\d+)/g)].map(м => Number(м[1]));
    if (номера.some(n => n < 1 || n > скобок)) провал('в шаблоне ' + исходник + ' номер $n больше числа скобок (' + скобок + ')');
  }
}

// 2. Покрытие: каждая русская фраза страницы переводится или названа в списке «не переводим».
const вариантыПроверки = ф => {
  const основа = ф.replace(/§/g, '7');
  return [основа, основа + ' 7', 'Имя' + основа, 'Имя ' + основа];
};
const переводится = ф => {
  if (Языки.словарь[ф]) return true;
  return вариантыПроверки(ф).some(в => Языки.текст(в, 'uk') !== в || Языки.текст(в, 'en') !== в);   // в украинском слово бывает тем же (пас, бот)
};
const использованоИсключение = new Set();
let всегоФраз = 0;
for (const файл of ИСТОЧНИКИ) {
  const текст = fs.readFileSync(path.join(корень, файл), 'utf8');
  const фразы = new Set(файл.endsWith('.html') ? фразыИзHtml(текст) : фразыИзJs(текст));
  if (!фразы.size) провал('в источнике не найдено ни одной русской фразы: ' + файл);
  всегоФраз += фразы.size;
  for (const ф of фразы) {
    const запись = НЕ_ПЕРЕВОДИМ.find(з => з[0] === ф);
    if (запись) { использованоИсключение.add(запись[0]); continue; }
    if (!переводится(ф)) провал('нет перевода [' + файл + ']: ' + ф.slice(0, 90));
  }
}
if (всегоФраз < 80) провал('найдено слишком мало русских фраз (' + всегоФраз + ') — поиск сломан');
for (const [ф] of НЕ_ПЕРЕВОДИМ) if (!использованоИсключение.has(ф)) провал('запись «не переводим» устарела: ' + ф);

// 3. Склеенные в коде фразы целиком.
for (const [ru, uk, en] of СБОРКИ) {
  if (Языки.текст(ru, 'uk') !== uk) провал('uk «' + ru + '» → «' + Языки.текст(ru, 'uk') + '», ждали «' + uk + '»');
  if (Языки.текст(ru, 'en') !== en) провал('en «' + ru + '» → «' + Языки.текст(ru, 'en') + '», ждали «' + en + '»');
}

console.log('языки-морской-бой: строк ' + строкиСловаря.length + ', шаблонов ' + шаблоныВФайле.length +
  ', фраз страницы ' + всегоФраз + ', исключений ' + НЕ_ПЕРЕВОДИМ.length);
console.log('Итого проверок: 3, провалов: ' + ошибки.length);
if (ошибки.length) {
  for (const о of ошибки.slice(0, 40)) console.log(' - ' + о);
  process.exit(1);
}
