const спать = (мс) => new Promise((ф) => setTimeout(ф, мс));

async function новаяСтраница(браузер, ш, в) {
  const окно = await браузер.newContext({ viewport: { width: ш, height: в }, hasTouch: true, deviceScaleFactor: 2 });
  const страница = await окно.newPage();
  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
    if (/Failed to load resource/.test(м.text())) return;
    красные.push('консоль: ' + м.text());
  });
  await подготовитьПодделку(страница, { версия: '8.0' });
  await страница.goto(АДРЕС);
  await спать(500);
  return { окно, страница, красные };
}

/** Тап по клетке доски по её имени поля («e2», «d5»…). */
async function тап(страница, поле) {
  await страница.evaluate((имя) => {
    const клетка = document.querySelector('[data-поле="' + имя + '"]');
    if (клетка) клетка.click();
  }, поле);
}

/** Сделать ход двумя касаниями — откуда и куда. Пауза внутри короткая
 *  (< 350 мс паузы бота перед ответом) — так тест успевает заглянуть
 *  на доску ПОСЛЕ хода человека, но ДО ответа робота. */
async function сходить(страница, откуда, куда) {
  await тап(страница, откуда);
  await спать(120);
  await тап(страница, куда);
  await спать(150);
}

/** Текст ленты записи ходов — с пробелом между узлами, как видит глаз. */
async function текстЛенты(страница) {
  return страница.evaluate(() => {
    const лента = document.getElementById('запись-ходов');
    if (!лента) return null;
    const части = [];
    for (const пара of лента.querySelectorAll('.запись-ходов__пара')) {
      for (const узел of пара.children) части.push((узел.textContent || '').trim());
    }
    return { текст: части.join(' '), детейВЛенте: лента.children.length };
  });
}

/** «05:03» → 303 секунды. */
function секундыИзТекста(текст) {
  const части = String(текст || '').split(':');
  if (части.length !== 2) return NaN;
  return Number(части[0]) * 60 + Number(части[1]);
}

/** Снимок плашки часов (текст, видимость, активность) по суффиксу «сверху»/«снизу». */
async function снимокЧасов(страница, суффикс) {
  return страница.evaluate((с) => {
    const узел = document.getElementById('часы-' + с);
    const текст = document.getElementById('часы-' + с + '-текст');
    return {
      видна: !!узел && узел.offsetParent !== null,
      активна: !!узел && узел.classList.contains('панель-игрока-шахмат__часы--активны'),
      текст: текст ? текст.textContent : ''
    };
  }, суффикс);
}

