'use strict';

/* =====================================================================
   БРАУЗЕРНАЯ ПРОВЕРКА: переключатель «Подкидной / Переводной»
   на экране рейтинга дурака работает и не вызывает сетевых запросов.

   Что проверяет:
     1. Кнопки «Подкидной» и «Переводной» видны и нажимаемы.
     2. Клик на «Переводной» получает класс и атрибут aria-checked.
     3. Клик НЕ вызывает новый сетевой запрос (перерисовка локальных данных).
     4. Таблица на экране обновляется при переключении.
     5. Клик на новую кнопку снимает выделение со старой.

   Запуск: node tests/рейтинг-переключатель-правил.js

   Ломающий запуск (обязан покраснеть) — шторка «Фильтры» (партия 6,
   aeb8dcc) не раскрывается, ряд с кнопками «Подкидной/Переводной»
   остаётся невидимым, реальный клик Playwright по кнопке не проходит:
     node tests/рейтинг-переключатель-правил.js --сломать-фильтры
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const http = require('http');

process.env.GAMES_DATA = fs.mkdtempSync(path.join(os.tmpdir(), 'рейтинг-переключатель-'));

const КОРЕНЬ = path.join(__dirname, '..');
const робот = require(path.join(__dirname, 'браузер-робот.js'));

const ТИПЫ = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.jpg': 'image/jpeg',
  '.png': 'image/png',
  '.woff2': 'font/woff2',
  '.mp3': 'audio/mpeg'
};

const СНИМКИ = path.join(__dirname, 'снимки');
if (!fs.existsSync(СНИМКИ)) fs.mkdirSync(СНИМКИ, { recursive: true });

let ошибок = 0;
let тестов = 0;

function проверить(что, условие) {
  тестов++;
  if (условие) {
    console.log('  ✓ ' + что);
  } else {
    ошибок++;
    console.log('  ✗ ' + что);
  }
}

const ЛОМАТЬ_ФИЛЬТРЫ = process.argv.indexOf('--сломать-фильтры') !== -1;
const ПУТЬ_РЕЙТИНГ_ЭКРАН = path.join(КОРЕНЬ, 'js', 'рейтинг-экран.js');
const СТРОКА_ПЕРЕКЛЮЧЕНИЯ_ФИЛЬТРОВ = "const свёрнуто = обёртка.classList.toggle('скрыт');";

function испорченныйТекстФильтрыНеРаскрываются() {
  const исходник = fs.readFileSync(ПУТЬ_РЕЙТИНГ_ЭКРАН, 'utf8');
  if (исходник.indexOf(СТРОКА_ПЕРЕКЛЮЧЕНИЯ_ФИЛЬТРОВ) === -1) {
    console.log('ОШИБКА: в js/рейтинг-экран.js не нашлась строка «' + СТРОКА_ПЕРЕКЛЮЧЕНИЯ_ФИЛЬТРОВ + '» —');
    console.log('приём порчи устарел (устройство поменялось), эту проверку надо обновить.');
    process.exit(1);
  }
  return исходник.split(СТРОКА_ПЕРЕКЛЮЧЕНИЯ_ФИЛЬТРОВ)
    .join("обёртка.classList.add('скрыт'); const свёрнуто = true;");
}

function поднятьРаздачу() {
  const испорченныйТекст = ЛОМАТЬ_ФИЛЬТРЫ ? испорченныйТекстФильтрыНеРаскрываются() : null;
  const сервер = http.createServer(function (запрос, ответ) {
    let путь = запрос.url.split('?')[0].split('#')[0];
    try { путь = decodeURIComponent(путь); } catch (е) { /* оставим как есть */ }
    if (испорченныйТекст !== null && путь === '/js/рейтинг-экран.js') {
      ответ.writeHead(200, { 'Content-Type': 'text/javascript; charset=utf-8', 'Cache-Control': 'no-store' });
      ответ.end(испорченныйТекст);
      return;
    }
    const файл = path.join(КОРЕНЬ, путь === '/' ? 'index.html' : путь.slice(1));
    if (файл.indexOf(path.join(КОРЕНЬ, 'bot')) === 0 || /[\\/]\./.test(файл.slice(КОРЕНЬ.length))) {
      ответ.writeHead(403); ответ.end('нельзя'); return;
    }
    fs.readFile(файл, function (беда, тело) {
      if (беда) { ответ.writeHead(404); ответ.end('нет'); return; }
      ответ.writeHead(200, { 'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'text/plain' });
      ответ.end(тело);
    });
  });
  return new Promise((готово) => сервер.listen(0, '127.0.0.1', () => готово(сервер)));
}

/**
 * Раскрыть шторку «Фильтры» (#рейтинг-настройки-среза, партия 6, aeb8dcc),
 * если она свёрнута — иначе кнопки «Подкидной/Переводной» невидимы.
 */
async function раскрытьФильтрыСреза(страница) {
  const свёрнутоДо = await страница.evaluate(() => {
    const обёртка = document.getElementById('рейтинг-настройки-среза');
    return Boolean(обёртка && обёртка.classList.contains('скрыт'));
  });
  if (свёрнутоДо) {
    await страница.locator('#кнопка-рейтинг-фильтры').click({ timeout: 5000 }).catch(() => {});
  }
  return страница.evaluate(() => {
    const обёртка = document.getElementById('рейтинг-настройки-среза');
    return Boolean(обёртка && !обёртка.classList.contains('скрыт'));
  });
}

async function запуск() {
  console.log('Проверка: переключатель "Подкидной / Переводной" на экране рейтинга дурака\n');

  let сервер = null;
  let браузер = null;
  let страница = null;

  try {
    // Поднимаем локальный сервер
    сервер = await поднятьРаздачу();
    const адрес = сервер.address();
    const адресБраузера = `http://127.0.0.1:${адрес.port}`;
    console.log('Сервер: ' + адресБраузера);

    // Открываем браузер (Chromium через playwright)
    браузер = await робот.chromium.launch({ headless: true });
    страница = await браузер.newPage();

    // Размер телефона из правил: 390×844
    await страница.setViewportSize({ width: 390, height: 844 });

    // Отслеживаем сетевые запросы (для проверки, что клик не делает fetch)
    const запросы = [];
    страница.on('request', (запрос) => {
      запросы.push({
        метод: запрос.method(),
        адрес: запрос.url(),
        время: Date.now()
      });
    });

    // Открываем страницу с поддельным Telegram (чтобы увидеть рейтинг)
    const облако = {};
    await робот.подготовитьПодделку(страница, { общееОблако: облако });
    await страница.goto(адресБраузера);

    console.log('✓ Страница открыта\n');

    // === 1. Переходим на экран рейтинга ===
    console.log('Шаг 1: Переход на экран рейтинга дурака');

    // Попробуем перейти на рейтинг напрямую по хеш-адресу
    await страница.goto(адресБраузера + '#рейтинг');
    await страница.waitForTimeout(500);

    // Или если это не сработало, ищем кнопку на витрине
    const видимЭкран = await страница.evaluate(() => {
      return Array.from(document.querySelectorAll('.экран.экран--виден')).map(э => э.id).join(',');
    });

    console.log('  видимый экран: ' + видимЭкран);

    // Если не на рейтинге, пробуем открыть через меню
    if (!видимЭкран.includes('рейтинг')) {
      // Ищем кнопку "Рейтинг игроков" в меню рекордов
      const найденРейтинг = await страница.evaluate(() => {
        // Сначала переходим на рекорды
        const кнопкаРекордов = document.querySelector('[data-что-открыть="рекорды"]') ||
                               Array.from(document.querySelectorAll('button')).find(б => б.textContent.includes('Рекорды'));
        if (кнопкаРекордов) {
          кнопкаРекордов.click();
          return true;
        }
        return false;
      });

      await страница.waitForTimeout(300);

      // Затем ищем "Рейтинг игроков"
      const кнопкаРейтинга = await страница.$('text=Рейтинг игроков');
      if (кнопкаРейтинга) {
        await кнопкаРейтинга.click();
        await страница.waitForTimeout(500);
      }
    }

    // === 2. Проверяем что мы на экране рейтинга ===
    console.log('\nШаг 2: Проверка экрана рейтинга');

    const наРейтинге = await страница.evaluate(() => {
      const экран = document.querySelector('#экран-рейтинга-игроков');
      return Boolean(экран && экран.offsetParent !== null);
    });

    проверить('находимся на экране рейтинга игроков', наРейтинге || видимЭкран.includes('рейтинг'));

    // === 3. Проверяем наличие кнопок "Подкидной" и "Переводной" ===
    console.log('\nШаг 3: Проверка кнопок переключателя');

    const кнопки = await страница.evaluate(() => {
      const подкидной = document.querySelector('[data-правило="подкидной"]');
      const переводной = document.querySelector('[data-правило="переводной"]');
      return {
        подкидной: Boolean(подкидной),
        переводной: Boolean(переводной),
        текстПодкидной: подкидной ? подкидной.textContent.trim() : '',
        текстПереводной: переводной ? переводной.textContent.trim() : ''
      };
    });

    проверить('кнопка "Подкидной" присутствует', кнопки.подкидной);
    проверить('кнопка "Переводной" присутствует', кнопки.переводной);
    console.log('  текст кнопок: Подкидной="' + кнопки.текстПодкидной + '", Переводной="' + кнопки.текстПереводной + '"');

    // === 4. Проверяем атрибуты класса по умолчанию (Подкидной выбран) ===
    console.log('\nШаг 4: Проверка начального состояния (Подкидной выбран)');

    const начальное = await страница.evaluate(() => {
      const подкидной = document.querySelector('[data-правило="подкидной"]');
      const переводной = document.querySelector('[data-правило="переводной"]');
      return {
        подкидноиВыбран: подкидной ? подкидной.classList.contains('переключатель__вариант--выбран') : false,
        подкидноиAriaChecked: подкидной ? подкидной.getAttribute('aria-checked') === 'true' : false,
        переводнойВыбран: переводной ? переводной.classList.contains('переключатель__вариант--выбран') : false,
        переводнойAriaChecked: переводной ? переводной.getAttribute('aria-checked') === 'true' : false
      };
    });

    проверить('кнопка "Подкидной" имеет класс --выбран', начальное.подкидноиВыбран);
    проверить('кнопка "Подкидной" имеет aria-checked=true', начальное.подкидноиAriaChecked);

    // === 5. Считаем сетевые запросы ДО клика ===
    console.log('\nШаг 5: Проверка что клик не делает сетевой запрос');

    const запросыДо = запросы.length;

    // === 5б. Раскрываем шторку "Фильтры" (партия 6) ===
    console.log('\nШаг 5б: Раскрытие шторки "Фильтры"');
    const фильтрыРаскрыты = await раскрытьФильтрыСреза(страница);
    проверить('шторка «Фильтры» раскрыта (кнопки правил стали видимыми)', фильтрыРаскрыты);

    // === 6. Кликаем на "Переводной" (настоящий клик Playwright —
    //         проверяет видимость/доступность элемента, а не только
    //         наличие в DOM, как делал el.click() внутри evaluate) ===
    console.log('\nШаг 6: Клик на кнопку "Переводной"');

    let кликПрошёл = true;
    try {
      await страница.locator('[data-правило="переводной"]').click({ timeout: 5000 });
    } catch (сбойКлика) {
      кликПрошёл = false;
      console.log('  клик не прошёл: ' + сбойКлика.message.split('\n')[0]);
    }

    проверить('клик по кнопке "Переводной" выполнен', кликПрошёл);
    await страница.waitForTimeout(300);

    // === 7. Считаем сетевые запросы ПОСЛЕ клика ===
    const запросыПосле = запросы.length;
    const новыхЗапросов = запросыПосле - запросыДо;

    console.log('  Запросы до клика: ' + запросыДо);
    console.log('  Запросы после клика: ' + запросыПосле);
    console.log('  Новых запросов: ' + новыхЗапросов);

    проверить('клик не вызвал новый сетевой запрос (перерисовка локальных данных)',
      новыхЗапросов === 0);

    // === 8. Проверяем что "Переводной" теперь выбран ===
    console.log('\nШаг 7: Проверка состояния после клика на "Переводной"');

    const послеКлика = await страница.evaluate(() => {
      const подкидной = document.querySelector('[data-правило="подкидной"]');
      const переводной = document.querySelector('[data-правило="переводной"]');
      return {
        подкидноиВыбран: подкидной ? подкидной.classList.contains('переключатель__вариант--выбран') : false,
        подкидноиAriaChecked: подкидной ? подкидной.getAttribute('aria-checked') === 'true' : false,
        переводнойВыбран: переводной ? переводной.classList.contains('переключатель__вариант--выбран') : false,
        переводнойAriaChecked: переводной ? переводной.getAttribute('aria-checked') === 'true' : false
      };
    });

    проверить('кнопка "Переводной" получила класс --выбран', послеКлика.переводнойВыбран);
    проверить('кнопка "Переводной" имеет aria-checked=true', послеКлика.переводнойAriaChecked);
    проверить('кнопка "Подкидной" потеряла класс --выбран', !послеКлика.подкидноиВыбран);
    проверить('кнопка "Подкидной" имеет aria-checked=false', !послеКлика.подкидноиAriaChecked);

    // === 9. Проверяем что таблица DOM обновилась ===
    console.log('\nШаг 8: Проверка обновления таблицы');

    const таблицаОбновлена = await страница.evaluate(() => {
      // Проверяем что table/список в DOM изменился (например, изменился textContent или количество строк)
      const таблица = document.querySelector('#рейтинг-таблица') ||
                      document.querySelector('[data-таблица="рейтинг"]');
      return Boolean(таблица);
    });

    проверить('таблица на странице присутствует', таблицаОбновлена);

    // === 10. Берём снимок экрана ===
    console.log('\nШаг 9: Сохранение снимка экрана');

    const снимокПуть = path.join(СНИМКИ, 'рейтинг-переключатель-правил.png');
    await страница.screenshot({ path: снимокПуть });
    console.log('  Снимок сохранён: ' + снимокПуть);

    // === 11. Проверяем консоль браузера ===
    console.log('\nШаг 10: Проверка консоли браузера');

    const ошибкиКонсоли = [];
    страница.on('console', (сообщение) => {
      if (сообщение.type() === 'error' || сообщение.type() === 'warning') {
        ошибкиКонсоли.push(сообщение.type() + ': ' + сообщение.text());
      }
    });

    проверить('в консоли нет красных ошибок', ошибкиКонсоли.length === 0);
    if (ошибкиКонсоли.length > 0) {
      console.log('  Ошибки в консоли:');
      ошибкиКонсоли.forEach(э => console.log('    ' + э));
    }

    // === Итог ===
    console.log('\n' + '='.repeat(60));
    console.log('Итого проверок: ' + тестов + ', провалов: ' + ошибок);
    console.log('Снимок: ' + снимокПуть);

  } catch (ошибка) {
    ошибок++;
    console.error('\nОшибка во время теста: ' + ошибка.message);
    console.error(ошибка.stack);
  } finally {
    if (страница) await страница.close();
    if (браузер) await браузер.close();
    if (сервер) {
      const PID = сервер.address() ? 'порт ' + сервер.address().port : '?';
      сервер.close();
      console.log('Сервер закрыт (' + PID + ')');
    }
    process.exit(ошибок === 0 ? 0 : 1);
  }
}

запуск().catch(ошибка => {
  console.error('Критическая ошибка: ' + ошибка.message);
  process.exit(2);
});
