'use strict';

/* =====================================================================
   КОПИЯ ИГРЫ СО СТАРЫМ ПРАВИЛОМ ДОБОРА — чтобы проверки умели краснеть.

   Зачем это нужно. Зелёная проверка стоит чего-то только тогда, когда
   она умеет краснеть. Про добор это особенно верно: правило поменяли
   («делим остаток по одной карте по кругу» вместо «первый набирает себе
   полные шесть»), и надо доказать, что новые проверки поймали бы
   возврат старого правила, а не просто согласились с игрой.

   Как устроено. Сам файл игры мы НЕ ТРОГАЕМ — он чужой. Здесь делается
   его копия во временной папке, и в копии одна-единственная функция
   «добрать» заменена прежней. Рядом кладётся папка server/ со сборкой
   вида: она пишет require('../js/game.js') и поэтому подхватит именно
   копию, а не настоящую игру. Иначе в одной проверке оказались бы две
   разные книги правил.

   Кому пригодится:
       const { собратьКопию } = require('./копия-игры-со-старым-добором.js');
       const путь = собратьКопию();      // путь к копии js/game.js
       const игра = require(путь);
   И то же самое доводом для больших прогонов:
       node tests/автопрогон-правил-компанией.js 40 <путь>
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

/* Прежнее правило добора, слово в слово тем, чем оно было до 9 сентября:
   очередь та же, но каждый по очереди набирает СЕБЕ полные шесть, пока
   в колоде что-то есть. Отсюда и жалоба владельца: «у меня 2 карты
   и у соперника 2, а в колоде 4» — первый забирал все четыре. */
const СТАРОЕ_ПРАВИЛО =
  'function добрать(партия) {\n' +
  '  /* СТАРОЕ ПРАВИЛО, подставлено проверкой из tests/копия-игры-со-старым-добором.js.\n' +
  '     В настоящей игре этого кода нет. */\n' +
  '  const очередь = порядокДобора(партия);\n' +
  '  for (const игрок of очередь) {\n' +
  '    while (партия.руки[игрок].length < КАРТ_В_РУКЕ && партия.колода.length > 0) {\n' +
  '      партия.руки[игрок].push(партия.колода.shift());\n' +
  '    }\n' +
  '  }\n' +
  '}\n';

const НАЧАЛО = 'function добрать(партия) {';

/**
 * Подменить в тексте игры одну функцию целиком.
 * Конец функции ищем по закрывающей скобке в начале строки: все правила
 * в js/game.js написаны на верхнем уровне файла, и другой такой скобки
 * внутри тела не встретится.
 */
function подменитьДобрать(текст) {
  const начало = текст.indexOf(НАЧАЛО);
  if (начало === -1) {
    throw new Error('В js/game.js не нашлась функция «добрать» — проверка устарела ' +
      'и молча ничего не подменит. Загляните в игру: как теперь называется добор?');
  }
  const конец = текст.indexOf('\n}\n', начало);
  if (конец === -1) {
    throw new Error('Не нашёлся конец функции «добрать» в js/game.js.');
  }
  return текст.slice(0, начало) + СТАРОЕ_ПРАВИЛО + текст.slice(конец + 3);
}

/**
 * Собрать копию игры со старым добором и вернуть путь к её js/game.js.
 * Копия живёт во временной папке машины, в проект не попадает.
 */
function собратьКопию() {
  const корень = path.join(__dirname, '..');
  const текст = fs.readFileSync(path.join(корень, 'js', 'game.js'), 'utf8');
  const подменённый = подменитьДобрать(текст);
  if (подменённый.indexOf('СТАРОЕ ПРАВИЛО, подставлено проверкой') === -1) {
    throw new Error('Подмена правила не сработала — краснеть проверке будет нечем.');
  }

  const папка = path.join(os.tmpdir(), 'игра-со-старым-добором');
  fs.mkdirSync(path.join(папка, 'js'), { recursive: true });
  fs.mkdirSync(path.join(папка, 'server'), { recursive: true });
  const кудаИгра = path.join(папка, 'js', 'game.js');
  fs.writeFileSync(кудаИгра, подменённый, 'utf8');
  /* Сборка вида лежит рядом нарочно: она пишет require('../js/game.js'),
     то есть возьмёт нашу копию. Большие прогоны ищут её именно так. */
  fs.copyFileSync(path.join(корень, 'server', 'партия-по-сети.js'),
                  path.join(папка, 'server', 'партия-по-сети.js'));
  return кудаИгра;
}

module.exports = { собратьКопию: собратьКопию, СТАРОЕ_ПРАВИЛО: СТАРОЕ_ПРАВИЛО };

/* Запустили напрямую — просто скажем, где лежит копия. */
if (require.main === module) {
  console.log(собратьКопию());
}
