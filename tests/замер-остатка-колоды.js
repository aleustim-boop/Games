/* Доводы командной строки: число партий — как раньше, первым голым
   числом; «--правила=ПУТЬ» — необязательный, отдельно, не мешает
   позиции числа. Нужен для ломающего запуска: подсунуть вместо
   настоящей игры испорченную копию и убедиться, что пороги ниже
   провалят её. */
const СЫРЫЕ_ДОВОДЫ = process.argv.slice(2);
function читатьДовод(имя) {
  const флаг = имя + '=';
  const найден = СЫРЫЕ_ДОВОДЫ.find(function (а) { return а.indexOf(флаг) === 0; });
  return найден ? найден.slice(флаг.length) : null;
}
const ЧИСЛОВЫЕ_ДОВОДЫ = СЫРЫЕ_ДОВОДЫ.filter(function (а) { return а.indexOf('--') !== 0; });
const ПАРТИЙ = Number(ЧИСЛОВЫЕ_ДОВОДЫ[0]) || 600;
const ПУТЬ_НАСТОЯЩЕЙ_ИГРЫ = path.join(__dirname, '..', 'js', 'game.js');
const ПУТЬ_ПРАВИЛ = читатьДовод('--правила')
  ? path.resolve(читатьДовод('--правила'))
  : ПУТЬ_НАСТОЯЩЕЙ_ИГРЫ;
const ПРЕДЕЛ_ХОДОВ = 900;      // больше — считаем, что партия ходит по кругу
const КАРТ_В_РУКЕ = 6;

/** Снимок перед ходом: по нему потом видно, кто сколько добрал. */
function снимок(игра, партия) {
  const руки = {};
  for (const имя of партия.игроки) руки[имя] = партия.руки[имя].length;
  let наСтоле = 0;
  for (const пара of партия.стол) наСтоле += пара.защита ? 2 : 1;
  return {
    руки: руки,
    колода: партия.колода.length,
    наСтоле: наСтоле,
    берёт: партия.берёт === true,
    защитник: игра.защищается(партия),
    очередь: игра.порядокДобора(партия)
  };
}

/**
 * Разглядеть добор, случившийся на этом ходу.
 * Колода не уменьшилась — добора не было, смотреть нечего.
 */
function осмотретьДобор(партия, до, счёт) {
  if (партия.колода.length >= до.колода) return;

  const добрал = {};
  const нехватка = {};
  for (const имя of до.очередь) {
    // Тот, кто взял карты со стола, пришёл к добору уже с ними на руках.
    const соСтола = (до.берёт && имя === до.защитник) ? до.наСтоле : 0;
    const былоПередДобором = до.руки[имя] + соСтола;
    добрал[имя] = партия.руки[имя].length - былоПередДобором;
    нехватка[имя] = Math.max(0, КАРТ_В_РУКЕ - былоПередДобором);
  }

  const обделённые = до.очередь.filter(function (имя) { return добрал[имя] < нехватка[имя]; });
  if (обделённые.length === 0) return;      // колоды хватило на всех — делить было нечего

  счёт.случаев++;
  счёт.вЭтойПартии++;

  const первый = до.очередь[0];
  const второй = до.очередь[1];
  if (добрал[первый] === до.колода) счёт.первыйЗабралВсё++;
  if (второй && добрал[второй] === 0 && нехватка[второй] > 0) счёт.второйБезКарт++;
  const ктоТоПустой = до.очередь.some(function (имя) {
    return нехватка[имя] > 0 && добрал[имя] === 0;
  });
  if (ктоТоПустой) счёт.ктоТоБезКарт++;

  // Самый большой разрыв между двумя нуждавшимися — по нему видно «поровну ли».
  let разрыв = 0;
  for (const кто of до.очередь) {
    for (const другой of до.очередь) {
      if (кто === другой) continue;
      if (добрал[другой] >= нехватка[другой]) continue;   // ему хватило, он не в счёт
      разрыв = Math.max(разрыв, добрал[кто] - добрал[другой]);
    }
  }
  счёт.разрывВсего += разрыв;
  счёт.разрывМакс = Math.max(счёт.разрывМакс, разрыв);
}

/** Одна партия двумя ботами. Отвечает: доиграна ли до конца. */
function сыгратьПартию(игра, зерно, счёт) {
  генератор.поставитьЗерно(зерно);
  const партия = игра.создатьПартию();
  счёт.вЭтойПартии = 0;

  let ходов = 0;
  while (!партия.завершена && ходов < ПРЕДЕЛ_ХОДОВ) {
    ходов++;
    const кто = игра.ктоХодит(партия);
    if (кто === null) break;
    const до = снимок(игра, партия);
    игра.ходБота(партия, кто);
    осмотретьДобор(партия, до, счёт);
  }
  if (счёт.вЭтойПартии > 0) счёт.партийСНехваткой++;
  return партия.завершена;
}

/** Прогнать все партии одной книгой правил. */
function прогнать(игра, партий) {
  const счёт = {
    партий: 0, доиграно: 0, партийСНехваткой: 0, вЭтойПартии: 0,
    случаев: 0, первыйЗабралВсё: 0, второйБезКарт: 0, ктоТоБезКарт: 0,
    разрывВсего: 0, разрывМакс: 0
  };
  for (let н = 1; н <= партий; н++) {
    счёт.партий++;
    if (сыгратьПартию(игра, н * 7919, счёт)) счёт.доиграно++;
  }
  return счёт;
}

/** Доля в процентах, посчитанная от числа случаев. */
function доля(сколько, изСкольких) {
  if (!изСкольких) return '—';
  return Math.round((сколько / изСкольких) * 100) + '%';
}

function напечатать(название, счёт) {
  console.log('\n' + название);
  console.log('  партий сыграно: ' + счёт.партий + ', доиграно до конца: ' + счёт.доиграно);
  console.log('  колоды не хватило: ' + счёт.случаев + ' раз (в ' + счёт.партийСНехваткой + ' партиях)');
  console.log('  первый по очереди забрал ВСЮ колоду: ' + счёт.первыйЗабралВсё +
    ' (' + доля(счёт.первыйЗабралВсё, счёт.случаев) + ' случаев)');
  console.log('  второй по очереди остался без карт: ' + счёт.второйБезКарт +
    ' (' + доля(счёт.второйБезКарт, счёт.случаев) + ')');
  console.log('  хоть кто-то нуждавшийся остался без карт: ' + счёт.ктоТоБезКарт +
    ' (' + доля(счёт.ктоТоБезКарт, счёт.случаев) + ')');
  const среднийРазрыв = счёт.случаев ? (счёт.разрывВсего / счёт.случаев).toFixed(2) : '—';
  console.log('  разрыв в картах между добравшими: в среднем ' + среднийРазрыв +
    ', самый большой ' + счёт.разрывМакс);
}

