function поднятьСервер() {
  return new Promise(function (готово, беда) {
    const дитя = spawn('node', [path.join(КОРЕНЬ, 'tests', 'локальный-сервер.js'), String(ПОРТ)]);
    let вывод = '';
    const срок = setTimeout(function () {
      дитя.kill();
      беда(new Error('локальный сервер не поднялся за 8 секунд'));
    }, 8000);
    дитя.stdout.on('data', function (кусок) {
      вывод += кусок;
      if (/сервер запущен/.test(вывод)) { clearTimeout(срок); готово(дитя); }
    });
    дитя.on('error', беда);
  });
}

async function новаяСтраница(браузер) {
  const контекст = await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
  const страница = await контекст.newPage();
  const красные = [];
  страница.on('pageerror', function (о) { красные.push('падение: ' + о.message); });
  страница.on('console', function (м) {
    if (м.type() !== 'error') return;
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
    красные.push('консоль: ' + м.text());
  });
  await подготовитьПодделку(страница, { версия: '8.0' });
  return { контекст: контекст, страница: страница, красные: красные };
}

/** Экран с этим id видим (класс «экран--виден»)? Ждём с опросом, не бросаем. */
async function дождатьсяЭкрана(страница, id, мс) {
  try {
    await страница.waitForFunction(function (и) {
      const э = document.getElementById(и);
      return Boolean(э && э.classList.contains('экран--виден'));
    }, id, { timeout: мс || 6000 });
    return true;
  } catch (сбой) {
    return false;
  }
}

async function состояниеСтрелки(страница) {
  return страница.evaluate(function () {
    return {
      видна: !!(window.Telegram && window.Telegram.WebApp && window.Telegram.WebApp.BackButton &&
        window.Telegram.WebApp.BackButton.isVisible),
      слушателей: (window.__дневник && window.__дневник.события.backButtonClicked || []).length
    };
  });
}

/** Позвать обработчик стрелки Telegram — тем же приёмом, что и настоящее нажатие. */
async function нажатьНазад(страница) {
  return страница.evaluate(function () {
    if (!window.ПоддельныйТелеграм) return false;
    window.ПоддельныйТелеграм.нажатьНазад();
    return true;
  });
}

async function путь(страница) {
  try { return await страница.evaluate(function () { return location.pathname; }); }
  catch (сбой) { return null; } // страница уже уходит — контекст мог умереть на полуслове
}

/** Ждём, что адрес страницы изменится (значит — ушли с неё). */
async function ждатьИзменения(страница, старый, мс) {
  const край = Date.now() + (мс || 3000);
  while (Date.now() < край) {
    const новый = await путь(страница);
    if (новый === null || новый !== старый) return true;
    await спать(120);
  }
  return false;
}

/** Ломающий запуск в браузере: подменяем функцию ПОСЛЕ загрузки страницы через evaluate.

    ПОЧЕМУ ЧЕРЕЗ evaluate А НЕ КОПИЯ ФАЙЛА?
    Браузерные проверки говорят с сервером на ОСНОВА (http://127.0.0.1:порт/).
    Чтобы подсунуть копию файла, нужен свой сервер с портом. Его нет, и поднимать
    его для браузерной части дорого (другой Node процесс, синхронизация).

    Поэтому пока используем подмену через evaluate — это нарочно неправильно,
    чтобы показать, что браузерная часть не совпадает с Node-частью. Когда
    будет свой сервер для ломающего запуска — переделать на чтение копии файла
    с поддельного сервера. */
async function применитьЛомку(страница) {
  if (!СЛОМАТЬ) return;
  await страница.evaluate(function () {
    if (window.Телеграм) {
      // Подменяем функцию на пустышку, как в Node-части (но через evaluate, а не копию файла).
      window.Телеграм.вернутьПрежнююСтрелку = function () { /* ломающий запуск: стек перестаёт восстанавливаться */ };
    }
  });
}

/**
 * Общий сценарий для шашек, шахмат и нард — они устроены одинаково (Э3
 * плана штаб/план-единый-стиль.md): лобби с нижней полосой вкладок
 * «Рейтинг»/«Профиль». «Рейтинг» по-прежнему открывает напрямую
 * js/рейтинг-экран.js (id «экран-рейтинга-игроков»). «Профиль» С
 * КОММИТА 646df4c «Профиль по макету» устроен уже НЕ в один шаг:
 * вкладка открывает НОВЫЙ экран js/профиль-экран.js (id
 * «экран-профиля-игрока»), а «Как я играю» (прежний ЭКРАН_СЧЁТА
 * «экран-рейтинга» из js/рейтинг-экран.js) — это кнопка ВНУТРИ него
 * («#кнопка-профиля-как-я-играю»), а не сама вкладка. «Назад» с обеих
 * служебных дверей ходит через одну и ту же общую дверь window.Телеграм.
 *
 * Дорога: лобби → «Рейтинг» → переключить пару игр внутри рейтинга
 * (контроль — стек не должен расти от переключений) → стрелка (1) →
 * лобби → «Профиль» (экран профиля игрока) → кнопка «Как я играю»
 * (ищем её на экране профиля, ноль — уже провал) → экран «Как я играю» →
 * стрелка (1) → назад на экран профиля, РОВНО один шаг, не сразу в
 * лобби → стрелка (2) → лобби → стрелка ЕЩЁ РАЗ (шаг 3 ниже) — вот тут
 * и сидела исходная поломка: раньше второе нажатие било в пустоту,
 * теперь обязано увести со страницы, как кнопка «‹» в лобби. Второй шаг
 * профиля (стрелка (2), из экрана профиля в лобби) — это МЕСТО, где
 * ломающий запуск теперь тоже обязан покраснеть: если стек не
 * восстанавливается, «Как я играю» так и останется висеть на стрелке, и
 * второе нажатие внутри самого блока «Профиль» не долетит до лобби же.
 * Финальное «увести со страницы» (шаг 3) проверяем ОДИН раз в конце —
 * это подтверждено чтением кода (js/рейтинг-экран.js — «назадИзРейтинга»
 * и «назадИзСчёта» вызывают ровно одну и ту же
 * window.Телеграм.вернутьПрежнююСтрелку).
 */
async function проверитьИгру(браузер, конфиг) {
  console.log('\n=== ' + конфиг.имя + ': лобби → «Рейтинг»/«Профиль» → стрелка Telegram ===');
  const { контекст, страница, красные } = await новаяСтраница(браузер);
  try {
    await страница.goto(ОСНОВА + конфиг.файл);
    const лобби = await дождатьсяЭкрана(страница, 'экран-лобби', 6000);
    проверить(лобби, конфиг.имя + ': лобби показалось после загрузки страницы');
    if (!лобби) return;

    await применитьЛомку(страница);

    const доВкладки = await состояниеСтрелки(страница);
    проверить(доВкладки.видна, конфиг.имя + ': стрелка Telegram видна уже на лобби');

    // --- 1. Рейтинг: открыть, переключить пару игр, вернуться на шаг ---
    await страница.click(конфиг.вкладкаРейтинг);
    const рейтингОткрыт = await дождатьсяЭкрана(страница, 'экран-рейтинга-игроков', 4000);
    проверить(рейтингОткрыт, конфиг.имя + ': вкладка «Рейтинг» на нижней полосе открывает экран рейтинга игроков');

    if (рейтингОткрыт) {
      /* Контроль: переключение игры внутри рейтинга не должно заново
         класть дело стрелки в стек (см. js/рейтинг-экран.js «обновить»
         против «открыть» — кнопки переключателя зовут только «обновить»).

         УСТРОЙСТВО ЭКРАНА СМЕНИЛОСЬ: раньше это была «лента кнопок»
         вида «#кнопка-рейтинг-<ключ>» прямо на экране — такого узла
         в разметке больше нет. Сейчас переключение — это кнопка-триггер
         «#рейтинг-выбор-игры-кнопка» (её сегодняшний вид), которая
         открывает модальную панель «#рейтинг-панель-игр» со строкой
         поиска и списком пунктов «#рейтинг-панель-игр-пункт-<ключ>»
         (js/рейтинг-экран.js: «убедитьсяЧтоЕстьВыборИгры»,
         «открытьПанельВыбораИгры», «заполнитьСписокИгр»,
         «выбратьИгруИзПанели»). Старый селектор ловил count()===0 на
         каждом шаге и молчал («if (нашлось) { … }» без ветки провала) —
         цикл не кликал вообще ничего, а единственная проверка ниже была
         тривиально верна независимо от того, произошло ли переключение.
         Здесь на каждом шаге явный «количество > 0» с провалом, а не
         тихий пропуск. */
      const кнопкаВыбораИгры = '#рейтинг-выбор-игры-кнопка';
      const естьКнопкаВыбораИгры = await страница.locator(кнопкаВыбораИгры).count();
      проверить(естьКнопкаВыбораИгры > 0,
        конфиг.имя + ': на экране рейтинга нашлась кнопка выбора игры (переключатель), не ноль');

      if (естьКнопкаВыбораИгры > 0) {
        const подписьДо = (await страница.locator(кнопкаВыбораИгры).textContent() || '').trim();

        await страница.click(кнопкаВыбораИгры);
        const панельОткрылась = await страница.waitForFunction(function () {
          const п = document.getElementById('рейтинг-панель-игр');
          return Boolean(п) && !п.classList.contains('скрыт');
        }, null, { timeout: 2000 }).then(function () { return true; }).catch(function () { return false; });
        проверить(панельОткрылась,
          конфиг.имя + ': клик по кнопке выбора игры открывает панель со списком игр');

        if (панельОткрылась) {
          const числоПунктов = await страница.locator('#рейтинг-панель-игр-список .рейтинг-панель-игр__пункт').count();
          проверить(числоПунктов > 0,
            конфиг.имя + ': в панели выбора игры нашлись пункты списка, не ноль: ' + числоПунктов);

          const другаяИгра = ['дурак', 'шахматы', 'шашки', 'нарды'].find(function (к) { return к !== конфиг.ключ; });
          const пунктДругойИгры = '#рейтинг-панель-игр-пункт-' + другаяИгра;
          const естьПунктДругойИгры = await страница.locator(пунктДругойИгры).count();
          проверить(естьПунктДругойИгры > 0,
            конфиг.имя + ': в панели нашёлся пункт другой игры «' + другаяИгра + '», не ноль');

          if (естьПунктДругойИгры > 0) {
            await страница.click(пунктДругойИгры);
            await спать(150);

            const панельЗакрыласьПослеВыбора = await страница.evaluate(function () {
              const п = document.getElementById('рейтинг-панель-игр');
              return Boolean(п) && п.classList.contains('скрыт');
            });
            проверить(панельЗакрыласьПослеВыбора,
              конфиг.имя + ': выбор игры из панели закрывает панель');

            const подписьПосле = (await страница.locator(кнопкаВыбораИгры).textContent() || '').trim();
            проверить(Boolean(подписьПосле) && подписьПосле !== подписьДо,
              конфиг.имя + ': после выбора другой игры подпись кнопки-переключателя реально сменилась (было «' +
              подписьДо + '», стало «' + подписьПосле + '»)');

            // Возвращаем рейтинг на свою игру — переключение здесь не
            // самоцель, а контроль стрелки; дальше по сценарию открываем
            // «Профиль» и ждём стрелку именно у конфиг.имя.
            await страница.click(кнопкаВыбораИгры);
            await спать(100);
            const пунктСвоейИгры = '#рейтинг-панель-игр-пункт-' + конфиг.ключ;
            const естьПунктСвоейИгры = await страница.locator(пунктСвоейИгры).count();
            if (естьПунктСвоейИгры > 0) {
              await страница.click(пунктСвоейИгры);
              await спать(100);
            } else {
              // Не нашли свой же пункт после переключения — это тоже
              // поломка (панель/список развалились), а не повод молчать.
              проверить(false, конфиг.имя + ': после переключений не нашёлся пункт своей игры «' + конфиг.ключ + '» — не смогли вернуться');
            }
          }
        }
      }

      const рейтингВсёЕщёОткрыт = await страница.evaluate(function () {
        return document.getElementById('экран-рейтинга-игроков').classList.contains('экран--виден');
      });
      проверить(рейтингВсёЕщёОткрыт,
        конфиг.имя + ' (контроль): переключение игр внутри рейтинга не закрывает и не ломает экран');

      await нажатьНазад(страница);
      const вЛоббиИзРейтинга = await дождатьсяЭкрана(страница, 'экран-лобби', 3000);
      проверить(вЛоббиИзРейтинга,
        конфиг.имя + ': первое нажатие стрелки из рейтинга (после переключений) возвращает в лобби — не второй раз подряд, ровно один шаг');
    }

    // --- 2. Профиль: экран профиля игрока → «Как я играю» → назад дважды ---
    // С коммита 646df4c «Профиль по макету» вкладка «Профиль» открывает
    // НЕ «Как я играю» напрямую, а новый общий экран js/профиль-экран.js
    // (id «экран-профиля-игрока»); «Как я играю» (js/рейтинг-экран.js,
    // ЭКРАН_СЧЁТА «экран-рейтинга») — кнопка ВНУТРИ него,
    // «#кнопка-профиля-как-я-играю» (js/профиль-экран.js, строка ~41).
    await страница.click(конфиг.вкладкаПрофиль);
    const профильОткрыт = await дождатьсяЭкрана(страница, 'экран-профиля-игрока', 4000);
    проверить(профильОткрыт, конфиг.имя + ': вкладка «Профиль» на нижней полосе открывает экран профиля игрока');

    const кнопкаКакЯИграю = '#кнопка-профиля-как-я-играю';
    const естьКнопкаКакЯИграю = профильОткрыт ? await страница.locator(кнопкаКакЯИграю).count() : 0;
    проверить(профильОткрыт && естьКнопкаКакЯИграю > 0,
      конфиг.имя + ': на экране профиля нашлась кнопка «Как я играю», не ноль');

    let счётОткрыт = false;
    if (профильОткрыт && естьКнопкаКакЯИграю > 0) {
      await страница.click(кнопкаКакЯИграю);
      счётОткрыт = await дождатьсяЭкрана(страница, 'экран-рейтинга', 4000);
    }
    проверить(счётОткрыт, конфиг.имя + ': кнопка «Как я играю» на экране профиля открывает «Как я играю»');

    // Стрелка (1): «Как я играю» → назад — обязана вернуть РОВНО на экран
    // профиля, не сразу в лобби (тут и сидела бы поломка стека — см.
    // комментарий к проверитьИгру выше).
    let профильСоСчёта = false;
    if (счётОткрыт) {
      await нажатьНазад(страница);
      профильСоСчёта = await дождатьсяЭкрана(страница, 'экран-профиля-игрока', 3000);
    }
    проверить(профильСоСчёта,
      конфиг.имя + ': первое нажатие стрелки из «Как я играю» возвращает на экран профиля — ровно один шаг, не сразу в лобби');

    // Стрелка (2): экран профиля → назад — в лобби. Если стек не
    // восстановился на первом шаге, тут стрелка так и останется висеть
    // на «назад из „Как я играю“» и в лобби не долетит.
    let вЛоббиИзПрофиля = false;
    if (профильСоСчёта) {
      await нажатьНазад(страница);
      вЛоббиИзПрофиля = await дождатьсяЭкрана(страница, 'экран-лобби', 3000);
    }
    проверить(вЛоббиИзПрофиля, конфиг.имя + ': второе нажатие стрелки — с экрана профиля — возвращает в лобби');

    // --- 3. Само нажатие «в шаге бага»: ЕЩЁ раз, теперь на лобби ---
    // Раньше именно это нажатие bilo в пустоту — дело стрелки застревало
    // на «назад из рейтинга/профиля» навсегда. Теперь стрелке должно
    // вернуться то дело, что было на ней ДО служебных экранов (своя
    // дверь «назад» лобби), и оно уводит со страницы на index.html.
    const путьДоВторого = await путь(страница);
    await нажатьНазад(страница);
    const ушли = await ждатьИзменения(страница, путьДоВторого, 3000);
    проверить(ушли, конфиг.имя +
      ': ещё одно нажатие стрелки после лобби уводит со страницы (как «‹» в лобби), а не висит мёртвым делом «назад из рейтинга»');

    // Всегда проверяем адрес, даже если не ушли (при ломающем запуске).
    // При ломающем запуске стрелка застревает на лобби, и эта проверка падает.
    await спать(300);
    const итог = (await путь(страница)) || '';
    проверить(/index\.html/.test(итог), конфиг.имя + ': нажатие увело именно на витрину (index.html)');

    проверить(красные.length === 0, конфиг.имя + ': консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));
  } finally {
    await контекст.close();
  }
}

/**
 * Дурак: своя дорога, своя память возврата (window.вернутьсяОткудаПришли),
 * поэтому и проверка своя.
 *   витрина (дом, стрелки нет вовсе) → «Рейтинг» → назад → витрина →
 *     лишнее нажатие ничего не портит (слушать уже нечего);
 *   лобби → «Рейтинг» → назад → лобби → назад ещё раз → витрина;
 *   лобби → «Профиль» (экран профиля игрока, с 646df4c «Профиль по
 *     макету») → кнопка «Как я играю» → экран «Как я играю» → назад
 *     (ровно один шаг, обратно на экран профиля) → назад (в лобби) →
 *     назад ещё раз (на витрину) — на index.html «Как я играю» открывается
 *     кликом по чужой готовой кнопке «#кнопка-мой-счёт» (см. «открытьСчёт»
 *     в js/рейтинг-экран.js, ветка для index.html), а «назад» с неё ходит
 *     через свою же общую память (js/game.js), поэтому у дурака здесь
 *     на один шаг больше, чем у «Рейтинга».
 */
async function дуракСтрелка(браузер) {
  console.log('\n=== Дурак: витрина/лобби → «Рейтинг»/«Профиль» → стрелка Telegram ===');
  const { контекст, страница, красные } = await новаяСтраница(браузер);
  try {
    await страница.goto(ОСНОВА);
    const витрина = await дождатьсяЭкрана(страница, 'экран-витрины', 6000);
    проверить(витрина, 'дурак: витрина видна сразу после загрузки');
    if (!витрина) return;

    await применитьЛомку(страница);

    // --- Уровень витрины: «Рейтинг» ---
    await страница.click('#кнопка-вкладка-профиль');
    const рейтингС1 = await дождатьсяЭкрана(страница, 'экран-рейтинга-игроков', 4000);
    проверить(рейтингС1, 'дурак: «Рейтинг» с витрины открывает экран рейтинга игроков');

    await нажатьНазад(страница);
    const наВитрине1 = await дождатьсяЭкрана(страница, 'экран-витрины', 3000);
    проверить(наВитрине1, 'дурак: первое нажатие стрелки из рейтинга (с витрины) возвращает на витрину');

    const состояниеНаВитрине = await состояниеСтрелки(страница);
    проверить(!состояниеНаВитрине.видна, 'дурак: на витрине (дома) стрелка спрятана — уходить больше некуда');

    // Лишнее нажатие на витрине: слушать уже нечего, страница не должна
    // ни упасть, ни застрять на чём-то чужом.
    await нажатьНазад(страница);
    await спать(200);
    const всёЕщёВитрина = await страница.evaluate(function () {
      return document.getElementById('экран-витрины').classList.contains('экран--виден');
    });
    проверить(всёЕщёВитрина, 'дурак: лишнее нажатие на витрине ничего не портит — она и так дома');

    // --- Уровень лобби: «Рейтинг» — здесь есть настоящий «второй шаг» ---
    await страница.click('#кнопка-игра-дурак');
    const лобби = await дождатьсяЭкрана(страница, 'экран-лобби', 4000);
    проверить(лобби, 'дурак: с витрины попали в лобби дурака');

    await страница.click('#лобби-вкладка-рейтинг');
    const рейтингС2 = await дождатьсяЭкрана(страница, 'экран-рейтинга-игроков', 4000);
    проверить(рейтингС2, 'дурак: «Рейтинг» из лобби открывает тот же экран рейтинга');

    await нажатьНазад(страница);
    const вЛобби = await дождатьсяЭкрана(страница, 'экран-лобби', 3000);
    проверить(вЛобби, 'дурак: первое нажатие стрелки из рейтинга (из лобби) возвращает в лобби');

    await нажатьНазад(страница);
    const наВитрине2 = await дождатьсяЭкрана(страница, 'экран-витрины', 3000);
    проверить(наВитрине2, 'дурак: второе нажатие из лобби поднимается ещё на шаг — на витрину, не зависает');

    // --- «Профиль» из лобби: экран профиля игрока → «Как я играю» → назад трижды ---
    // Та же перестройка, что и у шашек/шахмат/нард (коммит 646df4c
    // «Профиль по макету»): «Профиль» открывает не «Как я играю» напрямую,
    // а экран js/профиль-экран.js («экран-профиля-игрока»), «Как я играю» —
    // кнопка внутри него.
    await страница.click('#кнопка-игра-дурак');
    await дождатьсяЭкрана(страница, 'экран-лобби', 4000);
    await страница.click('#лобби-вкладка-профиль');
    const профильД = await дождатьсяЭкрана(страница, 'экран-профиля-игрока', 4000);
    проверить(профильД, 'дурак: «Профиль» из лобби открывает экран профиля игрока');

    const естьКнопкаКакЯИграюД = профильД ? await страница.locator('#кнопка-профиля-как-я-играю').count() : 0;
    проверить(профильД && естьКнопкаКакЯИграюД > 0,
      'дурак: на экране профиля нашлась кнопка «Как я играю», не ноль');

    let счёт = false;
    if (профильД && естьКнопкаКакЯИграюД > 0) {
      await страница.click('#кнопка-профиля-как-я-играю');
      счёт = await дождатьсяЭкрана(страница, 'экран-рейтинга', 4000);
    }
    проверить(счёт, 'дурак: кнопка «Как я играю» на экране профиля открывает «Как я играю»');

    let профильСоСчёта = false;
    if (счёт) {
      await нажатьНазад(страница);
      профильСоСчёта = await дождатьсяЭкрана(страница, 'экран-профиля-игрока', 3000);
    }
    проверить(профильСоСчёта,
      'дурак: первое нажатие стрелки из «Как я играю» возвращает на экран профиля — ровно один шаг');

    let вЛоббиСоСчёта = false;
    if (профильСоСчёта) {
      await нажатьНазад(страница);
      вЛоббиСоСчёта = await дождатьсяЭкрана(страница, 'экран-лобби', 3000);
    }
    проверить(вЛоббиСоСчёта, 'дурак: второе нажатие стрелки — с экрана профиля — возвращает в лобби');

    let наВитринеСоСчёта = false;
    if (вЛоббиСоСчёта) {
      await нажатьНазад(страница);
      наВитринеСоСчёта = await дождатьсяЭкрана(страница, 'экран-витрины', 3000);
    }
    проверить(наВитринеСоСчёта, 'дурак: третье нажатие — с лобби — поднимается на витрину, не зависает');

    проверить(красные.length === 0, 'дурак: консоль чистая' + (красные.length ? ': ' + красные.join(' | ') : ''));
  } finally {
    await контекст.close();
  }
}


