/** Поддельный Telegram для песочницы: помнит, показана ли стрелка,
    и умеет «нажать» на неё — позвать все обработчики backButtonClicked. */
function собратьТелеграмNode() {
  const слушатели = {};
  const состояние = { видна: false };
  const telegram = {
    onEvent: function (имя, cb) { (слушатели[имя] = слушатели[имя] || []).push(cb); },
    offEvent: function (имя, cb) {
      слушатели[имя] = (слушатели[имя] || []).filter(function (х) { return х !== cb; });
    },
    BackButton: {
      show: function () { состояние.видна = true; },
      hide: function () { состояние.видна = false; }
    }
  };
  return {
    telegram: telegram,
    состояние: состояние,
    нажать: function () { (слушатели.backButtonClicked || []).slice().forEach(function (cb) { cb(); }); }
  };
}

/** Свежая песочница с js/telegram.js внутри и своим поддельным Telegram.
    исходник опционален: если передан, используется вместо оригинального файла. */
function новаяПесочница(исходник) {
  const среда = собратьТелеграмNode();
  const результат = поднятьTelegramJS({
    telegram: среда.telegram,
    исходник: исходник // если исходник не передан, поднятьTelegramJS прочитает файл с диска
  });
  const Телеграм = результат.окно.Телеграм;
  if (!Телеграм || typeof Телеграм.показатьСтрелку !== 'function' ||
      typeof Телеграм.вернутьПрежнююСтрелку !== 'function' ||
      typeof Телеграм.спрятатьСтрелку !== 'function') {
    throw new Error('window.Телеграм не собрался целиком (нет нужных дверей)');
  }
  return { среда: среда, Телеграм: Телеграм };
}

/** Прогнать все сценарии проверки стека стрелки. Исходник опционален (по умолчанию читается с диска). */
function прогнатьСценарииNode(исходник) {
  let проба;
  try {
    проба = новаяПесочница(исходник);
  } catch (сбой) {
    console.log('  ПРОВЕРИТЬ НЕ УДАЛОСЬ: js/telegram.js не поднялся в песочнице (' +
      (сбой && сбой.message || сбой) + ') — перехожу к проверке в браузере.');
    return false; // не смогли поднять — скипаем эту часть
  }
  проверить(Boolean(проба.Телеграм), 'Node: window.Телеграм собрался в песочнице');

  // --- Сценарий 1: показатьСтрелку(A) → показатьСтрелку(Б) → вернутьПрежнююСтрелку() → нажатие зовёт A ---
  {
    const { среда, Телеграм } = новаяПесочница(исходник);
    let вызA = 0, вызБ = 0;
    Телеграм.показатьСтрелку(function () { вызA++; });
    Телеграм.показатьСтрелку(function () { вызБ++; });
    Телеграм.вернутьПрежнююСтрелку();
    среда.нажать();
    проверить(вызA === 1 && вызБ === 0,
      'сценарий 1: показатьСтрелку(A) → показатьСтрелку(Б) → вернутьПрежнююСтрелку() → нажатие зовёт A');
    проверить(среда.состояние.видна === true,
      'сценарий 1: после возврата стрелка видна (не спряталась зря)');
  }

  // --- Сценарий 2: показатьСтрелку одной и той же функции дважды не растит стек ---
  {
    const { среда, Телеграм } = новаяПесочница(исходник);
    let a = 0, b = 0;
    const делоА = function () { a++; };
    Телеграм.показатьСтрелку(делоА);
    Телеграм.показатьСтрелку(делоА); // та же ссылка на функцию — дубль в стек попасть не должен
    Телеграм.показатьСтрелку(function () { b++; });
    Телеграм.вернутьПрежнююСтрелку();
    среда.нажать();
    проверить(a === 1 && b === 0,
      'сценарий 2: дубль показатьСтрелку(A) не растит стек — возврат поднимает A ровно один раз');
    Телеграм.вернутьПрежнююСтрелку(); // если бы дубль всё же лёг в стек — тут снова встала бы A
    проверить(среда.состояние.видна === false,
      'сценарий 2: второй возврат — стек уже пуст, стрелка прячется, а не показывает A ещё раз');
  }

  // --- Сценарий 3: пять разных замыканий подряд → возврат поднимает не больше двух ---
  {
    const { среда, Телеграм } = новаяПесочница(исходник);
    const метки = [];
    for (let n = 1; n <= 5; n++) {
      Телеграм.показатьСтрелку((function (число) { return function () { метки.push(число); }; })(n));
    }
    метки.length = 0;
    Телеграм.вернутьПрежнююСтрелку(); среда.нажать();
    проверить(метки.join(',') === '4',
      'сценарий 3: после пяти разных показов первый возврат поднимает дело №4');
    метки.length = 0;
    Телеграм.вернутьПрежнююСтрелку(); среда.нажать();
    проверить(метки.join(',') === '3',
      'сценарий 3: второй возврат поднимает дело №3');
    метки.length = 0;
    Телеграм.вернутьПрежнююСтрелку(); среда.нажать();
    проверить(метки.length === 0 && среда.состояние.видна === false,
      'сценарий 3: третий возврат — глубже двух уровней стек не хранит, стрелка прячется');
  }

  // --- Сценарий 4: спрятатьСтрелку() чистит стек ---
  {
    const { среда, Телеграм } = новаяПесочница(исходник);
    Телеграм.показатьСтрелку(function () {});
    Телеграм.показатьСтрелку(function () {}); // теперь в стеке одно прежнее дело
    Телеграм.спрятатьСтрелку();
    проверить(среда.состояние.видна === false, 'сценарий 4: спрятатьСтрелку прячет стрелку сразу');
    Телеграм.вернутьПрежнююСтрелку();
    проверить(среда.состояние.видна === false,
      'сценарий 4: после спрятатьСтрелку стек уже чист — возврат не поднимает старое дело, просто прячет');
  }

  return true; // успешно прогнали
}

