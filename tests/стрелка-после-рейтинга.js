/** Создать и испортить копию js/telegram.js для ломающего запуска.

    КАК ПОРТИМ:
    В функции вернутьПрежнююСтрелку убираем вызов стекСтрелки.pop(), заменяя его
    на var прежнееДело = null. Это значит:
    - стек больше не восстанавливается (переменная прежнееДело пуста)
    - функция продолжает ходить дальше, но с пустым делом
    - все сценарии, которые проверяют восстановление из стека, падают
    - сценарии, которые проверяют спрятатьСтрелку, остаются зелёными
      (потому что спрятатьСтрелку не зависит от pop())

    Возвращает текст испорченного файла, предварительно сверив, что замена
    прошла успешно (если нет — выходит с ошибкой). */
function создатьСломанныйИсходник() {
  const исходный = fs.readFileSync(path.join(КОРЕНЬ, 'js', 'telegram.js'), 'utf8');

  // Заменяем pop() на null, чтобы стек перестал восстанавливаться.
  const сломанный = исходный.replace(
    /function вернутьПрежнююСтрелку\(\) \{\s+if \(стекСтрелки\.length === 0\) return спрятатьСтрелку\(\);\s+var прежнееДело = стекСтрелки\.pop\(\);/,
    'function вернутьПрежнююСтрелку() {\n    if (стекСтрелки.length === 0) return спрятатьСтрелку();\n    var прежнееДело = null; // ломающий запуск: pop() убран, стек не восстанавливается'
  );

  // Сверяем, что текст действительно изменился (иначе поломка не применилась).
  if (исходный === сломанный) {
    console.error('ОШИБКА: поломка не применилась — текст файла не изменился. Может быть, сигнатура функции вернутьПрежнююСтрелку изменилась?');
    process.exit(1);
  }

  console.log('  [поломка применилась: pop() убран из вернутьПрежнююСтрелку]');
  return сломанный;
}

