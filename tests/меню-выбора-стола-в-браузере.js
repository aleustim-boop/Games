/* =====================================================================
   ПРОВЕРКА ВЫБОРА СТОЛА С БОТАМИ — прямо в браузере.

   11 сентября прежнее меню (три ряда кнопок «Сколько играет», «Правила»,
   «Кто против кого», строка-пояснение и экран «Игра с ботом» с пятью
   кнопками) заменили лобби и три шага по макетам владельца. Проверка
   переписана на шаги, имя файла и дверь window.ПроверкаМеню оставлены
   прежними — по ним её зовут из записей штаба.

   Что ушло вместе с меню и больше НЕ проверяется (смысла нет):
     • «Парами само ставит четверых, а другое число само гасит Парами» —
       теперь при «2 на 2» другие числа просто выключены, а «Каждый за
       себя» возвращает прежнее число (это проверяется ниже, в п. 2);
     • строка-пояснение под рядами и «не накрыла ли её кнопка Играть» —
       такой строки больше нет; её место заняли «почему только четверо»
       на шаге 2 и сводка стола на шаге 3 (проверяются в п. 2 и п. 4);
     • пять кнопок экрана «Игра с ботом» («Играть», «Как играть»,
       «Рекорды», «Звук», «Назад») — «Как играть», «Рекорды» и «Звук»
       ушли в лист «⋯»; их проверяет tests/лобби-в1.js.

   Что проверяет теперь (всё — настоящими нажатиями по кнопкам шагов):
     1) каждый состав 2–6 при «Каждый за себя» и оба свода правил
        выбираются, отмечаются и ложатся в память браузера;
     2) «2 на 2»: ровно четверо, 2/3/5/6 выключены настоящим disabled
        и объяснены словами, видно «почему»; «Каждый за себя» возвращает
        прежнее число, и память его не затирает;
     3) колода: на шестерых 36 карт выключена с объяснением, 52 — можно;
        выбор колоды и сложности ложится в память;
     4) сводка стола на шаге 3 не пустая и называет выбранное число;
     5) на каждом шаге до каждой кнопки можно долистать и попасть
        пальцем (на месте кнопки лежит она, а не что-то поверх).

   Как пользоваться (консоль браузера на открытой странице игры):
       await ПроверкаМеню.пройти();     // прогон на нынешнем размере окна
       ПроверкаМеню.отчёт();            // что нашлось

   ВАЖНО: проверка нажимает кнопки по-настоящему, поэтому она ПЕРЕПИШЕТ
   запомненный выбор. В конце она возвращает то, что было записано до неё
   (а в самой странице выбор останется до перезагрузки).
   ===================================================================== */

(function () {
  'use strict';

  /* Ключи памяти — у самого файла пути, а не второй копией здесь. */
  const К = (window.ДуракПуть && window.ДуракПуть.КЛЮЧИ_ПАМЯТИ) || {};

  const беды = [];
  const сделано = [];

  function ждать(мс) { return new Promise(function (г) { setTimeout(г, мс); }); }
  function беда(что, подробности) { беды.push(подробности ? что + ' — ' + подробности : что); }
  function проверить(условие, что, подробности) {
    сделано.push(что);
    if (!условие) беда(что, подробности);
  }
  const все = (выбор) => [].slice.call(document.querySelectorAll(выбор));
  const видимый = () => (document.querySelector('.экран.экран--виден') || {}).id || '';
  const память = (ключ) => localStorage.getItem(ключ);

  async function нажать(узел) { if (узел) { узел.click(); await ждать(40); } }
  const далее = () => нажать(document.querySelector('.экран.экран--виден [data-путь="далее"]'));
  const назад = () => нажать(document.querySelector('.экран.экран--виден [data-путь="назад"]'));
  const число = (n) => все('#путь-числа .числа__число').filter((к) => к.textContent.trim() === String(n))[0];
  const выбранноеЧисло = () => ((document.querySelector('#путь-числа .числа__число--выбран') || {}).textContent || '').trim();
  const форматы = () => все('#путь-форматы .переключатель__вариант');

  /** До шага N (1…3) дорогой человека: лобби → «Играть с ботами» → «Далее»… */
  async function кШагу(номер) {
    if (typeof показатьЛоббиДурака === 'function') показатьЛоббиДурака();
    await ждать(60);
    await нажать(document.getElementById('лобби-боты'));
    for (let i = 1; i < номер; i++) await далее();
    const ждём = ['', 'экран-путь-правила', 'экран-путь-игроки', 'экран-путь-настройки'][номер];
    проверить(видимый() === ждём, 'дошли до шага ' + номер, 'виден ' + видимый());
  }

  /**
   * До каждой кнопки видимого шага можно долистать и попасть пальцем.
   * Экран однажды (ещё в прежнем меню) приехал вовсе без прокрутки, и
   * кнопки ниже края стали недостижимы — ловим ровно этот случай.
   */
  function проверитьДостижимость(имяШага) {
    const экран = document.querySelector('.экран.экран--виден');
    if (!экран) { беда('нет видимого экрана — мерить нечего', имяШага); return; }
    const кнопки = все('#' + экран.id + ' button').filter((к) => {
      const с = getComputedStyle(к);
      return к.offsetParent !== null && с.visibility !== 'hidden';
    });
    проверить(кнопки.length > 0, имяШага + ': на шаге есть кнопки', 'ни одной видимой');
    for (const к of кнопки) {
      к.scrollIntoView({ block: 'nearest', inline: 'nearest' });
      const р = к.getBoundingClientRect();
      const влезла = р.top >= -0.5 && р.bottom <= window.innerHeight + 0.5 && р.left >= -0.5 && р.right <= window.innerWidth + 0.5;
      const подПальцем = document.elementFromPoint(р.left + р.width / 2, р.top + р.height / 2);
      const своя = Boolean(подПальцем) && (подПальцем === к || к.contains(подПальцем));
      const имя = (к.getAttribute('aria-label') || к.textContent || к.id || '').trim().replace(/\s+/g, ' ').slice(0, 30);
      проверить(влезла && своя, имяШага + ': до кнопки «' + имя + '» можно долистать и попасть пальцем',
        (влезла ? '' : 'лежит с ' + Math.round(р.top) + ' по ' + Math.round(р.bottom) + ' при окне ' + window.innerHeight + '; ') +
        (своя ? '' : 'палец попадает в «' + (подПальцем ? (подПальцем.id || подПальцем.className) : 'пустоту') + '»'));
    }
    экран.scrollTop = 0;
  }

  async function пройти() {
    беды.length = 0;
    сделано.length = 0;
    проверить(Boolean(К.игроков && К.переводной && К.парами && К.колода && К.сложность),
      'ключи памяти взяты у js/дурак-путь.js', JSON.stringify(К));
    if (беды.length) return отчёт();
    const былоВПамяти = {};
    for (const имя in К) былоВПамяти[К[имя]] = память(К[имя]);

    /* --- 1. Составы 2–6 × оба свода правил --- */
    for (const правила of ['подкидной', 'переводной']) {
      await кШагу(1);
      await нажать(document.querySelector('#путь-правила-варианты [data-вариант="' + правила + '"]'));
      const отмечен = (document.querySelector('#путь-правила-варианты .вариант--выбран') || { dataset: {} }).dataset.вариант;
      проверить(отмечен === правила, 'нажал «' + правила + '» — он и отмечен', 'отмечен: ' + отмечен);
      проверить(память(К.переводной) === (правила === 'переводной' ? 'да' : 'нет'),
        'в память лёг свод правил «' + правила + '»', 'в памяти: ' + память(К.переводной));
      await далее();
      await нажать(форматы()[0]);
      for (const мест of [2, 3, 4, 5, 6]) {
        await нажать(число(мест));
        проверить(выбранноеЧисло() === String(мест), 'нажал «' + мест + '» — столько и отмечено', 'отмечено: ' + выбранноеЧисло());
        проверить(память(К.игроков) === String(мест) && память(К.парами) !== 'да',
          'в память легло ' + мест + ' мест, каждый за себя', 'в памяти: мест=' + память(К.игроков) + ', парами=' + память(К.парами));
      }
    }

    /* --- 2. «2 на 2» --- */
    await кШагу(2);
    await нажать(форматы()[0]);
    await нажать(число(5));
    await нажать(форматы()[1]);
    const выключены = все('#путь-числа .числа__число').filter((к) => к.disabled).map((к) => к.textContent.trim()).join(',');
    const безСлов = все('#путь-числа .числа__число').filter((к) => к.disabled && !(к.getAttribute('title') || '').trim()).length;
    const почему = document.getElementById('путь-почему-число');
    проверить(выбранноеЧисло() === '4', '«2 на 2» — отмечено четверо', 'отмечено: ' + выбранноеЧисло());
    проверить(выключены === '2,3,5,6', '«2 на 2» — 2, 3, 5 и 6 выключены настоящим disabled', 'выключены: ' + выключены);
    проверить(безСлов === 0, 'у каждого выключенного числа есть объяснение словами', 'без слов: ' + безСлов);
    проверить(Boolean(почему) && !почему.classList.contains('скрыт') && почему.textContent.trim().length > 0,
      'при «2 на 2» видно, почему только четверо');
    проверить(память(К.парами) === 'да', 'в память легло «2 на 2»', 'в памяти: ' + память(К.парами));
    await нажать(форматы()[0]);
    проверить(выбранноеЧисло() === '5', '«Каждый за себя» вернул прежнее число (5)', 'отмечено: ' + выбранноеЧисло());
    проверить(память(К.игроков) === '5' && память(К.парами) === 'нет',
      'в памяти число «каждый за себя» не затёрто четвёркой', 'мест=' + память(К.игроков) + ', парами=' + память(К.парами));
    проверитьДостижимость('шаг 2');

    /* --- 3. Колода и сложность на шестерых --- */
    await нажать(число(6));
    await далее();
    проверить(видимый() === 'экран-путь-настройки', '«Далее» со второго шага — на третий', 'виден ' + видимый());
    const колоды = все('#путь-колоды .переключатель__вариант');
    const к36 = колоды.filter((к) => /^36/.test(к.textContent.trim()))[0];
    const к52 = колоды.filter((к) => /^52/.test(к.textContent.trim()))[0];
    проверить(Boolean(к36) && к36.disabled && (к36.getAttribute('title') || '').length > 0,
      'на шестерых 36 карт выключена и объяснена', к36 ? 'disabled=' + к36.disabled + ', title=«' + (к36.getAttribute('title') || '') + '»' : 'кнопки 36 нет');
    проверить(Boolean(к52) && !к52.disabled, 'на шестерых 52 карты можно');
    await нажать(к52);
    проверить(память(К.колода) === '52', 'в память легла колода 52', 'в памяти: ' + память(К.колода));
    const сложно = все('#путь-сложность .переключатель__вариант').filter((к) => к.textContent.trim() === 'Сложно')[0];
    await нажать(сложно);
    проверить(память(К.сложность) === 'сложный', 'в память лёг уровень «сложный»', 'в памяти: ' + память(К.сложность));

    /* --- 4. Сводка стола --- */
    const главное = ((document.getElementById('путь-сводка-главное') || {}).textContent || '').trim();
    const подпись = ((document.getElementById('путь-сводка-подпись') || {}).textContent || '').trim();
    проверить(/6/.test(главное) && подпись.length > 0, 'сводка называет стол: «' + главное + '» / «' + подпись + '»');
    проверитьДостижимость('шаг 3');

    /* --- 5. Шаг 1 тоже весь достижим --- */
    await назад();
    await назад();
    проверить(видимый() === 'экран-путь-правила', 'дважды «‹» — снова шаг 1', 'виден ' + видимый());
    проверитьДостижимость('шаг 1');

    /* Возвращаем то, что было записано до проверки. */
    for (const ключ in былоВПамяти) {
      if (былоВПамяти[ключ] === null) localStorage.removeItem(ключ); else localStorage.setItem(ключ, былоВПамяти[ключ]);
    }
    if (typeof показатьЛоббиДурака === 'function') показатьЛоббиДурака();
    return отчёт();
  }

  function отчёт() {
    return {
      окно: window.innerWidth + '×' + window.innerHeight,
      проверок: сделано.length,
      бед: беды.length,
      беды: беды.slice(),
      итог: беды.length ? 'ЕСТЬ ЧТО ПОКАЗАТЬ ШТАБУ' : 'выбор стола на шагах ведёт себя правильно'
    };
  }

  window.ПроверкаМеню = { пройти: пройти, отчёт: отчёт };
})();
