/* =====================================================================
   ПРОВЕРКА КНОПОК «КАКОЙ БУДЕТ СТОЛ С БОТАМИ» — прямо в браузере.

   Зачем она нужна. Три ряда кнопок в меню («Сколько играет», «Правила»,
   «Кто против кого») живут в разметке и в оформлении, а не в правилах
   игры. Node их не видит вовсе: правила из js/game.js наружу отдают
   раздачу и ходы, а меню — нет. Поэтому проверка сделана браузерной:
   она честно НАЖИМАЕТ кнопки и смотрит, что получилось.

   Что проверяет:
     1) все составы 2–6, оба свода правил и «парами» вставляются;
     2) «Парами» само ставит четверых, а другое число мест само гасит
        «Парами» (в правилах игры парной игры на троих нет);
     3) выбор ложится в память браузера — тот же, что показан кнопками;
     4) испорченная запись в памяти приводится к разрешённой;
     5) строка-пояснение под кнопками не обрезана и не пуста;
     6) пояснение не спрятано под кнопкой «Играть» (в низком окне она
        прилипает к нижнему краю и может накрыть строку собой).

   Чего она НЕ делает: не играет партий и не проверяет правила — на это
   есть «автопрогон-правил-компанией.js» и «как-считается-итог-компанией.js».

   Как пользоваться (консоль браузера на открытой странице игры):
       await ПроверкаМеню.пройти();     // прогон на нынешнем размере окна
       ПроверкаМеню.отчёт();            // что нашлось

   ВАЖНО: проверка нажимает кнопки по-настоящему, поэтому она ПЕРЕПИШЕТ
   запомненный стол. В конце она возвращает то, что было записано до неё.
   ===================================================================== */

(function () {
  'use strict';

  const КЛЮЧ_МЕСТ = 'подкидной-дурак:мест-с-ботами';
  const КЛЮЧ_ПЕРЕВОДНОГО = 'подкидной-дурак:переводной-с-ботами';
  const КЛЮЧ_ПАР = 'подкидной-дурак:парами-с-ботами';

  const беды = [];
  const сделано = [];

  function ждать(мс) { return new Promise(function (г) { setTimeout(г, мс); }); }

  function беда(что, подробности) {
    беды.push(подробности ? что + ' — ' + подробности : что);
  }

  function проверить(условие, что, подробности) {
    сделано.push(что);
    if (!условие) беда(что, подробности);
  }

  function кнопка(ряд, значение) {
    return document.querySelector('#' + ряд + ' button[value="' + значение + '"]');
  }

  /** Какая кнопка в ряду отмечена как выбранная. */
  function выбрано(ряд) {
    const узел = document.getElementById(ряд);
    if (!узел) return null;
    const нажатые = [].filter.call(узел.querySelectorAll('.кнопка--выбор'), function (к) {
      return к.classList.contains('кнопка--активная');
    });
    if (нажатые.length !== 1) return '(отмечено кнопок: ' + нажатые.length + ')';
    return нажатые[0].getAttribute('value');
  }

  function пояснение() { return document.getElementById('меню-пояснение-стола'); }

  /** Вернуться в меню, откуда бы мы ни были. */
  function вМеню() {
    const выход = document.getElementById('кнопка-в-меню');
    if (выход) выход.click();
    const да = document.getElementById('кнопка-выход-да');
    if (да) да.click();
    const сИтога = document.getElementById('кнопка-в-меню-итог');
    if (сИтога) сИтога.click();
    for (const назад of ['кнопка-рекорды-назад', 'кнопка-правила-назад', 'кнопка-друг-назад']) {
      const у = document.getElementById(назад);
      if (у && у.offsetParent !== null) у.click();
    }
  }

  /** Строка-пояснение: есть текст, и он влез в отведённое место. */
  function проверитьПояснение(когда) {
    const п = пояснение();
    if (!п) { беда('нет строки-пояснения под кнопками', когда); return; }
    const текст = (п.textContent || '').trim();
    проверить(текст.length > 0, 'пояснение не пустое (' + когда + ')');
    проверить(п.scrollHeight <= п.clientHeight + 1,
      'пояснение влезло целиком (' + когда + ')',
      'нужно ' + п.scrollHeight + ' точек высоты, отведено ' + п.clientHeight);
  }

  /**
   * Не накрыла ли кнопка «Играть» строку-пояснение собой.
   * В низком окне (шторка Telegram) кнопка нарочно прилипает к нижнему
   * краю и лежит поверх списка. Пока меню не прокручено, она может
   * закрыть собой строку, которая объясняет выбранный стол.
   */
  function проверитьНаложение() {
    const меню = document.getElementById('экран-меню');
    const п = пояснение();
    const играть = document.getElementById('кнопка-играть');
    if (!меню || !п || !играть) return null;
    меню.scrollTop = 0;                    // так меню выглядит при открытии игры
    const а = п.getBoundingClientRect();
    const б = играть.getBoundingClientRect();
    const накрыто = Math.max(0, Math.min(а.bottom, б.bottom) - Math.max(а.top, б.top));
    проверить(накрыто < 2,
      'пояснение видно целиком, кнопка «Играть» его не накрывает',
      'накрыто ' + Math.round(накрыто) + ' точек из ' + Math.round(а.height) +
      ' (окно ' + window.innerWidth + '×' + window.innerHeight + ')');
    return Math.round(накрыто);
  }

  /** Кнопка «Играть» видна, не листая меню. */
  function проверитьВидимостьИграть() {
    const меню = document.getElementById('экран-меню');
    const играть = document.getElementById('кнопка-играть');
    if (!меню || !играть) return;
    меню.scrollTop = 0;
    const р = играть.getBoundingClientRect();
    проверить(р.bottom <= window.innerHeight + 0.5 && р.top >= -0.5,
      'кнопка «Играть» видна без прокрутки',
      'она лежит с ' + Math.round(р.top) + ' по ' + Math.round(р.bottom) +
      ' точку, а окно высотой ' + window.innerHeight);
  }

  async function пройти() {
    беды.length = 0;
    сделано.length = 0;

    const былоВПамяти = {
      мест: localStorage.getItem(КЛЮЧ_МЕСТ),
      переводной: localStorage.getItem(КЛЮЧ_ПЕРЕВОДНОГО),
      парами: localStorage.getItem(КЛЮЧ_ПАР)
    };

    вМеню();
    await ждать(200);

    for (const ряд of ['меню-выбор-мест', 'меню-выбор-правил', 'меню-выбор-пар']) {
      проверить(!!document.getElementById(ряд), 'в меню есть ряд «' + ряд + '»');
    }
    if (беды.length) return отчёт();

    /* --- 1. Каждый состав вставляется и запоминается --- */
    for (const мест of ['2', '3', '4', '5', '6']) {
      for (const правила of ['обычный', 'переводной']) {
        кнопка('меню-выбор-пар', 'каждый').click();
        кнопка('меню-выбор-мест', мест).click();
        кнопка('меню-выбор-правил', правила).click();
        await ждать(30);
        проверить(выбрано('меню-выбор-мест') === мест,
          'нажал «' + мест + '» — столько и отмечено', 'отмечено: ' + выбрано('меню-выбор-мест'));
        проверить(выбрано('меню-выбор-правил') === правила,
          'нажал «' + правила + '» — он и отмечен', 'отмечено: ' + выбрано('меню-выбор-правил'));
        проверить(localStorage.getItem(КЛЮЧ_МЕСТ) === мест,
          'в память легло ' + мест + ' мест', 'в памяти: ' + localStorage.getItem(КЛЮЧ_МЕСТ));
        проверить(localStorage.getItem(КЛЮЧ_ПЕРЕВОДНОГО) === (правила === 'переводной' ? 'да' : 'нет'),
          'в память лёг свод правил «' + правила + '»');
        проверитьПояснение(мест + ' мест, ' + правила);

        /* Пояснение про двойки обязано появляться ровно с пяти мест:
           с них правила берут колоду в 52 карты. */
        const текст = (пояснение().textContent || '');
        const обещаныДвойки = /двойк/i.test(текст);
        проверить(обещаныДвойки === (Number(мест) >= 5),
          'про двойки сказано ровно при 5 и 6 местах (сейчас ' + мест + ')',
          обещаныДвойки ? 'двойки обещаны' : 'двойки не обещаны');
      }
    }

    /* --- 2. «Парами» само ставит четверых --- */
    кнопка('меню-выбор-пар', 'каждый').click();
    кнопка('меню-выбор-мест', '5').click();
    await ждать(30);
    кнопка('меню-выбор-пар', 'парами').click();
    await ждать(30);
    проверить(выбрано('меню-выбор-мест') === '4',
      'нажал «Парами» при пятерых — места сами стали четырьмя',
      'отмечено мест: ' + выбрано('меню-выбор-мест'));
    проверить(выбрано('меню-выбор-пар') === 'парами', 'кнопка «Парами» осталась нажатой');
    проверить(localStorage.getItem(КЛЮЧ_МЕСТ) === '4' && localStorage.getItem(КЛЮЧ_ПАР) === 'да',
      'в память легли четверо и «парами»',
      'в памяти: мест=' + localStorage.getItem(КЛЮЧ_МЕСТ) + ', парами=' + localStorage.getItem(КЛЮЧ_ПАР));

    /* --- 3. Другое число мест само гасит «Парами» --- */
    for (const мест of ['2', '3', '5', '6']) {
      кнопка('меню-выбор-пар', 'парами').click();
      await ждать(20);
      кнопка('меню-выбор-мест', мест).click();
      await ждать(20);
      проверить(выбрано('меню-выбор-пар') === 'каждый',
        'нажал «' + мест + '» при включённом «Парами» — «Парами» погасло',
        'отмечено: ' + выбрано('меню-выбор-пар'));
      проверить(localStorage.getItem(КЛЮЧ_ПАР) === 'нет',
        'в память легло «парами: нет» после выбора ' + мест + ' мест');
    }

    /* --- 4. Испорченная запись в памяти приводится к разрешённой ---
       Страницу мы не перезагружаем (проверка живёт в этой же странице),
       поэтому смотрим только, что игра не рухнула и что записанное
       кнопками значение всегда из разрешённых. */
    const вПамяти = Number(localStorage.getItem(КЛЮЧ_МЕСТ));
    проверить(вПамяти >= 2 && вПамяти <= 6,
      'в памяти всегда разрешённое число мест', 'в памяти: ' + вПамяти);

    /* --- 5. Вёрстка меню на нынешнем размере окна --- */
    проверитьВидимостьИграть();
    const накрыто = проверитьНаложение();

    /* Возвращаем то, что было записано до проверки. */
    const вернуть = (ключ, значение) => {
      if (значение === null) localStorage.removeItem(ключ); else localStorage.setItem(ключ, значение);
    };
    вернуть(КЛЮЧ_МЕСТ, былоВПамяти.мест);
    вернуть(КЛЮЧ_ПЕРЕВОДНОГО, былоВПамяти.переводной);
    вернуть(КЛЮЧ_ПАР, былоВПамяти.парами);

    return отчёт(накрыто);
  }

  function отчёт(накрыто) {
    return {
      окно: window.innerWidth + '×' + window.innerHeight,
      проверок: сделано.length,
      бед: беды.length,
      беды: беды.slice(),
      накрытоПоясненияТочек: накрыто,
      итог: беды.length ? 'ЕСТЬ ЧТО ПОКАЗАТЬ ШТАБУ' : 'кнопки меню ведут себя правильно'
    };
  }

  window.ПроверкаМеню = { пройти: пройти, отчёт: отчёт };
})();
