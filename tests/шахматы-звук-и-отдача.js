'use strict';

/* =====================================================================
   ШАХМАТЫ: ЗВУК И ОТДАЧА ПОД ПАЛЬЦЕМ — проверка без браузера.

   Как устроено. Поддельный браузер (tests/поддельный-браузер.js) даёт
   документ и окно, мы кладём туда разметку шахматной страницы и по очереди
   запускаем настоящие файлы игры: правила, бота, звук, экран. Сверху —
   маленькая подделка звукового движка (её в поддельном браузере нет):
   она не издаёт ни звука, а записывает, какие частоты игра просила сыграть.
   Отдачу под пальцем ловим так же, как в tests/отдача-под-пальцем.js —
   поддельным HapticFeedback.

   Что проверяем:
     1. фигуру подняли — лёгкий отклик 'выбор';
     2. ход сделан — щелчок 262 Гц и отклик 'карта'; взятие — 196/147 и 'взятка';
     3. шах — свой сигнал 587/494 и отклик-предупреждение;
     4. так ходить нельзя — 150 Гц и отклик 'нельзя' (раньше игра молчала);
     5. не частим: тычок в занятое поле подряд не даёт очереди щелчков;
     6. мат — звук победы и отклик 'победа';
     7. выключатель звука: кнопка есть (её нет в разметке — игра ставит сама),
        глушит всё разом, вибрацию при этом не трогает, выбор переживает
        перезагрузку страницы;
     8. ход робота звучит так же, как свой;
     9. высоты сигналов совпадают с шашками: три игры сборника не должны
        звучать по-разному, когда происходит одно и то же.

   Запуск:  node tests/шахматы-звук-и-отдача.js
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const { КОРЕНЬ, поднять, сделатьПамять, сделатьДокумент } = require('./поддельный-браузер.js');

const беды = [];
function надо(условие, что) {
  if (!условие) беды.push(что);
}

function подождать(мс) {
  return new Promise(function (готово) { setTimeout(готово, мс); });
}

/* Подделка звукового движка: ничего не играет, только записывает частоты.
   Кладётся в страницу перед файлами игры — как настоящий AudioContext. */
const ПОДДЕЛКА_ЗВУКА = `
window.__частоты = [];
window.AudioContext = function () {
  return {
    state: 'running',
    currentTime: 0,
    destination: {},
    resume: function () {},
    createOscillator: function () {
      return {
        type: '', frequency: { setValueAtTime: function (ч) { window.__частоты.push(ч); } },
        connect: function () {}, start: function () {}, stop: function () {}
      };
    },
    createGain: function () {
      return {
        gain: { setValueAtTime: function () {}, exponentialRampToValueAtTime: function () {} },
        connect: function () {}
      };
    }
  };
};
`;

/** Разметка страницы шахмат — ровно те узлы, которые ищет js/шахматы-экран.js. */
function разметкаШахмат(документ) {
  const д = документ;
  const ряд = д.узел('div', { класс: 'ряд-кнопок' },
    д.узел('button', { id: 'кнопка-поворот', текст: 'Поворот доски: да' }),
    д.узел('button', { id: 'кнопка-метки', текст: 'Буквы и цифры: да' }),
    д.узел('button', { id: 'кнопка-назад', текст: '← Назад' }));

  д.body.appendChild(д.узел('div', { id: 'приложение' },
    д.узел('div', { id: 'доска', класс: 'доска-шахмат' }),
    д.узел('p', { id: 'строка-хода' }),
    д.узел('button', { id: 'уровень-лёгкий' }),
    д.узел('button', { id: 'уровень-обычный' }),
    д.узел('button', { id: 'уровень-сложный' }),
    д.узел('button', { id: 'кнопка-с-ботом' }),
    д.узел('button', { id: 'кнопка-вдвоём' }),
    ряд,
    д.узел('div', { id: 'экран-итога', класс: 'экран' },
      д.узел('h2', { id: 'заголовок-итога' }),
      д.узел('p', { id: 'причина-итога' }),
      д.узел('button', { id: 'кнопка-ещё' }),
      д.узел('button', { id: 'кнопка-другой-соперник' })),
    д.узел('div', { id: 'экран-превращения', класс: 'экран' },
      д.узел('button', { id: 'кнопка-превращение-отмена' }))));
}

/** Поднять страницу шахмат целиком: подделка звука, правила, бот, звук, экран. */
function поднятьШахматы(настройки) {
  const н = настройки || {};
  const документ = сделатьДокумент();
  разметкаШахмат(документ);

  const просьбыОтдачи = [];
  const части = ['js/шахматы-правила.js', 'js/шахматы-бот.js', 'js/шахматы-звук.js', 'js/шахматы-экран.js'];
  const исходник = ПОДДЕЛКА_ЗВУКА + '\n' +
    части.map(function (файл) { return fs.readFileSync(path.join(КОРЕНЬ, файл), 'utf8'); }).join('\n;\n');

  const стенд = поднять(исходник, {
    документ: документ,
    память: н.память || сделатьПамять(false),
    имяФайла: 'страница-шахмат.js',
    telegram: {
      version: '7.10',
      isVersionAtLeast: function () { return true; },
      HapticFeedback: {
        impactOccurred: function (сила) { просьбыОтдачи.push('удар:' + сила); },
        notificationOccurred: function (исход) { просьбыОтдачи.push('весть:' + исход); },
        selectionChanged: function () { просьбыОтдачи.push('выбор'); }
      }
    }
  });

  // Отдача живёт в js/telegram.js, а его мы не поднимаем: страница шахмат
  // и без него должна работать. Подкладываем ту же дверь вручную.
  стенд.окно.Телеграм = { отклик: function (вид) { просьбыОтдачи.push('отклик:' + вид); return true; } };
  стенд.отдача = просьбыОтдачи;
  стенд.частоты = стенд.окно.__частоты;
  стенд.тап = function (поле) {
    const клетка = документ.querySelector('[data-поле="' + поле + '"]');
    if (!клетка) { беды.push('на доске нет поля ' + поле); return; }
    клетка.click();
  };
  стенд.нажать = function (id) {
    const кнопка = документ.getElementById(id);
    if (!кнопка) { беды.push('нет кнопки ' + id); return; }
    кнопка.click();
  };
  стенд.очистить = function () {
    просьбыОтдачи.length = 0;
    стенд.окно.__частоты.length = 0;
  };
  return стенд;
}

/** Сделать ход двумя касаниями. */
function сходить(стенд, откуда, куда) {
  стенд.тап(откуда);
  стенд.тап(куда);
}

async function проверить() {
  // -------------------------------------------------------------------------
  // 1–2. Выбор фигуры и ход
  // -------------------------------------------------------------------------
  {
    const с = поднятьШахматы();
    с.нажать('кнопка-вдвоём');   // без робота: ходим за обе стороны сами
    с.очистить();

    с.тап('e2');
    надо(с.отдача.join(',') === 'отклик:выбор',
      'на поднятую фигуру ждали лёгкий отклик «выбор», а вышло: ' + с.отдача.join(','));

    с.очистить();
    с.тап('e4');
    надо(с.отдача.join(',') === 'отклик:карта',
      'на сделанный ход ждали отклик «карта», а вышло: ' + с.отдача.join(','));
    надо(с.частоты.join(',') === '262', 'ход должен щёлкать на 262 Гц, а сыграло: ' + с.частоты.join(','));
  }

  // -------------------------------------------------------------------------
  // 3. Взятие и шах
  // -------------------------------------------------------------------------
  {
    const с = поднятьШахматы();
    с.нажать('кнопка-вдвоём');
    сходить(с, 'e2', 'e4');
    сходить(с, 'd7', 'd5');
    с.очистить();
    сходить(с, 'e4', 'd5');   // пешка бьёт пешку
    надо(с.отдача.join(',') === 'отклик:выбор,отклик:взятка',
      'на взятие ждали отклик «взятка», а вышло: ' + с.отдача.join(','));
    надо(с.частоты.join(',') === '196,147', 'взятие должно звучать как бой в шашках (196 и 147), а сыграло: ' + с.частоты.join(','));
  }

  {
    const с = поднятьШахматы();
    с.нажать('кнопка-вдвоём');
    сходить(с, 'e2', 'e4');
    сходить(с, 'd7', 'd5');
    с.очистить();
    сходить(с, 'f1', 'b5');   // слон вышел с шахом чёрному королю
    надо(с.частоты.join(',') === '262,587,494',
      'после хода с шахом ждали щелчок хода и сигнал шаха (587, 494), а сыграло: ' + с.частоты.join(','));
    надо(с.отдача.join(',') === 'отклик:выбор,отклик:карта,отклик:нельзя',
      'шах должен чувствоваться отдельно от хода, а вышло: ' + с.отдача.join(','));
  }

  // -------------------------------------------------------------------------
  // 4–5. Отказ: раньше игра тут молчала, и не частим
  // -------------------------------------------------------------------------
  {
    const с = поднятьШахматы();
    с.нажать('кнопка-вдвоём');
    с.очистить();

    с.тап('a5');   // пустое поле: поднимать нечего
    надо(с.отдача.join(',') === 'отклик:нельзя',
      'на запрет ждали отклик «нельзя», а вышло: ' + с.отдача.join(','));
    надо(с.частоты.join(',') === '150', 'отказ должен звучать на 150 Гц, как у соседей, а сыграло: ' + с.частоты.join(','));

    с.очистить();
    с.тап('a5');
    с.тап('a5');
    с.тап('a5');
    надо(с.частоты.length === 0,
      'три тычка подряд не должны дать очередь щелчков, а сыграло: ' + с.частоты.join(','));

    await подождать(250);   // подождали дольше паузы между отказами
    с.тап('a5');
    надо(с.частоты.join(',') === '150', 'после паузы отказ снова должен звучать, а сыграло: ' + с.частоты.join(','));
  }

  // -------------------------------------------------------------------------
  // 6. Мат: «дурацкий мат» в четыре хода
  // -------------------------------------------------------------------------
  {
    const с = поднятьШахматы();
    с.нажать('кнопка-вдвоём');
    сходить(с, 'f2', 'f3');
    сходить(с, 'e7', 'e5');
    сходить(с, 'g2', 'g4');
    с.очистить();
    сходить(с, 'd8', 'h4');   // мат

    надо(с.документ.getElementById('заголовок-итога').textContent !== '', 'экран итога должен показаться');
    надо(с.частоты.join(',') === '262,523,659,784',
      'мат должен закончиться победными нотами (523, 659, 784), а сыграло: ' + с.частоты.join(','));
    надо(с.отдача.join(',') === 'отклик:выбор,отклик:карта,отклик:победа',
      'на мат ждали отклик победы, а вышло: ' + с.отдача.join(','));
  }

  // -------------------------------------------------------------------------
  // 7. Выключатель звука
  // -------------------------------------------------------------------------
  {
    const память = сделатьПамять(false);
    const с = поднятьШахматы({ память: память });
    const кнопка = с.документ.getElementById('кнопка-звук');
    надо(кнопка !== null, 'в разметке шахмат кнопки звука нет — игра должна поставить её сама');
    надо(кнопка && кнопка.textContent === 'Звук', 'подпись кнопки — короткая «Звук», как у шашек');
    надо(с.окно.ШахматыЗвук.включён() === true, 'по умолчанию звук включён');

    с.нажать('кнопка-вдвоём');
    с.очистить();
    с.нажать('кнопка-звук');   // выключили
    надо(с.окно.ШахматыЗвук.включён() === false, 'после нажатия звук должен выключиться');
    надо(кнопка.className.indexOf('кнопка--выключено') !== -1, 'выключенная кнопка должна это показывать');

    с.очистить();
    сходить(с, 'e2', 'e4');
    надо(с.частоты.length === 0, 'при выключенном звуке ходы звучать не должны: ' + с.частоты.join(','));
    надо(с.отдача.join(',') === 'отклик:выбор,отклик:карта',
      'выключенный звук не должен глушить вибрацию, а вышло: ' + с.отдача.join(','));

    надо(память.ключи().indexOf('sound_chess') !== -1,
      'выбор должен лечь под латинский ключ «sound_chess», а легли: ' + память.ключи().join(','));

    const снова = поднятьШахматы({ память: память });
    надо(снова.окно.ШахматыЗвук.включён() === false, 'выключенный звук должен пережить перезагрузку страницы');
    снова.нажать('кнопка-вдвоём');
    снова.очистить();
    сходить(снова, 'e2', 'e4');
    надо(снова.частоты.length === 0, 'после перезагрузки звук должен остаться выключенным');
  }

  // -------------------------------------------------------------------------
  // 8. Ход робота звучит так же, как свой
  // -------------------------------------------------------------------------
  {
    const с = поднятьШахматы();
    с.нажать('кнопка-с-ботом');
    сходить(с, 'e2', 'e4');    // свой ход
    с.очистить();
    await подождать(1500);     // робот думает и ходит
    надо(с.частоты.length > 0,
      'ход робота должен звучать, иначе человек слышит только себя, а сыграло: ' + с.частоты.join(','));
    надо(с.отдача.length > 0, 'ход робота должен и чувствоваться, а вышло: ' + с.отдача.join(','));
  }

  // -------------------------------------------------------------------------
  // 9. Одинаковые случаи — одинаковые высоты во всём сборнике
  // -------------------------------------------------------------------------
  {
    const шашки = fs.readFileSync(path.join(КОРЕНЬ, 'js', 'шашки-звук.js'), 'utf8');
    const шахматы = fs.readFileSync(path.join(КОРЕНЬ, 'js', 'шахматы-звук.js'), 'utf8');
    const общие = [
      ['ход', 'сигнал(262, 0.05)'],
      ['отказ', 'сигнал(150, 0.05)'],
      ['взятие и бой', 'сигнал(196, 0.10); сигнал(147, 0.16, 0.08)'],
      ['победа', 'сигнал(523'],
      ['поражение', 'сигнал(300'],
      ['ничья', 'сигнал(392']
    ];
    for (const [случай, строка] of общие) {
      надо(шашки.indexOf(строка) !== -1 && шахматы.indexOf(строка) !== -1,
        'случай «' + случай + '» должен звучать в шашках и шахматах одинаково (' + строка + ')');
    }
  }

  // -------------------------------------------------------------------------
  // 10. Вне Telegram: вибрации нет вовсе, и это ничего не ломает
  // -------------------------------------------------------------------------
  {
    const с = поднятьШахматы();
    delete с.окно.Телеграм;    // как в обычном браузере: двери отдачи нет
    с.нажать('кнопка-вдвоём');
    с.очистить();
    сходить(с, 'e2', 'e4');
    надо(с.частоты.join(',') === '262', 'без Telegram звук должен работать как обычно');
    надо(с.ошибкиКонсоли.length === 0,
      'без Telegram красных строк быть не должно, а там: ' + с.ошибкиКонсоли.join(' | '));
  }

  if (беды.length) {
    console.log('ПЛОХО, бед ' + беды.length + ':');
    for (const беда of беды) console.log('  — ' + беда);
    process.exit(1);
  }
  console.log('шахматы, звук и отдача: всё хорошо — ход, взятие, шах и отказ звучат и чувствуются, выключатель работает, ход робота слышно');
  process.exit(0);
}

проверить().catch(function (ошибка) {
  console.log('ПЛОХО: проверка сама сломалась — ' + (ошибка && ошибка.stack || ошибка));
  process.exit(1);
});
