/* ---- Все виды, ушедшие игрокам: потом ищем в них утечки ---- */
const виды = [];
function запомнитьВид(вид) { виды.push(вид); return вид; }

const ДАЛЁКОЕ_МОЛЧАНИЕ = комнаты.МОЛЧАНИЕ_ЭТО_ОБРЫВ + 8000;

function создать(настройки) {
  const итог = комнаты.создатьКомнату('10.0.0.1', настройки);
  if (!итог.ок) throw new Error('не создался стол: ' + итог.причина);
  запомнитьВид(итог.состояние);
  return итог;
}
function войти(код, настройки) {
  const итог = комнаты.войтиВКомнату(код, настройки);
  if (!итог.ок) throw new Error('не вошёл: ' + итог.причина);
  запомнитьВид(итог.состояние);
  return итог;
}
function ход(код, пропуск, намерение) {
  const н = комнаты.найтиИгрока(код, пропуск);
  const ответ = комнаты.сделатьХод(н.комната, н.ктоЯ, намерение);
  запомнитьВид(комнаты.показатьИгроку(н.комната, н.ктоЯ));
  return ответ;
}
/** Комната и место — без отметки «жив» (найтиИгрока её ставит, поэтому время молчания правим после). */
function место(код, пропуск) {
  return комнаты.найтиИгрока(код, пропуск);
}
function замолчать(код, пропуск) {
  const н = место(код, пропуск);
  н.комната.игроки[н.ктоЯ].последнийЗапрос = Date.now() - ДАЛЁКОЕ_МОЛЧАНИЕ;
}
/** Держать открытый опрос, но при этом молчать давно — «у экрана» только из-за опроса. */
const бросить = [];
function держатьОпрос(код, пропуск) {
  const н = место(код, пропуск);
  const перестать = комнаты.ждатьНовостей(н.комната, н.ктоЯ, н.комната.версия, 60000, function (вид) {
    if (вид) запомнитьВид(вид);
  });
  бросить.push(перестать);
  н.комната.игроки[н.ктоЯ].последнийЗапрос = Date.now() - ДАЛЁКОЕ_МОЛЧАНИЕ;
}
/** Партию считаем доигранной, не играя её: вестнику важен только этап «конец». */
function закончитьПартию(код, пропуск) {
  const н = место(код, пропуск);
  н.комната.этап = 'конец';
  н.комната.партия.завершена = true;
}

function взять(событие) {
  return {
    что: событие.что, игра: событие.игра, ктоИмя: событие.ктоИмя, ктоНомер: событие.ктоНомер,
    кому: событие.кому, хозяинНомер: событие.хозяинНомер,
    занятоМест: событие.занятоМест, всегоМест: событие.всегоМест, ссылка: событие.ссылка
  };
}
/** Сверить журнал с ожиданием целиком и очистить его. */
function ждём(что, ожидаемые) {
  const факт = журнал.splice(0).map(взять);
  const совпало = JSON.stringify(факт) === JSON.stringify(ожидаемые);
  сверить(совпало, что + ' (событий: ' + факт.length + ', ждали ' + ожидаемые.length + ')');
  if (!совпало) {
    console.log('       было:  ' + JSON.stringify(факт));
    console.log('       ждали: ' + JSON.stringify(ожидаемые));
  }
}

