/* =====================================================================
   Проверка вестника событий стола в server/комнаты.js (этап 2 плана
   штаб/план-лента-бота.md).

   Комнаты — модулем, без сети и без порта. Слушатель складывает события
   в журнал, а проверка сверяет: какие события родились, кому (с пометкой
   «у экрана»), сколько мест занято и всего, чья ссылка за стол.

   Что проверяем:
     — стол на двоих (дурак и шашки): второй сел → ровно одно «3а»;
     — стол на четверых: каждый вошедший → «2», последний → ещё и «3б» хозяину;
     — «Начать» → «3в» всем, кроме хозяина; бот и гость без номера не в «кому»;
     — «ещё» → «4» тем, кто не согласился; ушедший не в «кому»; повтор — ничего;
     — держит опрос → наЭкране:true; тот же, но страница скрыта → false;
       молчит дольше 12 с → false;
     — сбой слушателя не ломает вход за стол;
     — повторный вход с той же меткой событий не даёт;
     — откат входа (стол на двоих и на четверых): сидитЗаСтолом → false;
     — уЭкрана(код, номер): у экрана / скрыт / молчит / держит опрос;
     — ссылку за стол задаёт только хозяин (запомнитьСсылку): из настроек
       создания и входа она не берётся, гость её не задаёт, у стола без
       хозяина задаёт первый севший;
     — ни в одном виде игроку нет ссылки за стол и номеров Telegram, а тот
       же поиск в самой комнате их находит (опорная сверка).

   Запуск:
       node tests/лента-события-комнат.js
   Ломающие прогоны (оба обязаны покраснеть):
       node tests/лента-события-комнат.js --сломать
       node tests/лента-события-комнат.js --сломать-утечка
   «--сломать» — слушатель теряет каждое второе событие.
   «--сломать-утечка» — в один из видов игроку подкладываются ссылка за стол,
   поле «скрыта» и номер Telegram: поиск утечек обязан их увидеть.
   ===================================================================== */

