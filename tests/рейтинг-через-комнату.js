/* =====================================================================
   РЕЙТИНГ ЧЕРЕЗ НАСТОЯЩЕЕ ЗАСТОЛЬЕ КОМНАТЫ.

   Что проверяем. Комната по концу партии зовёт застольеДляРейтинга
   (server/комнаты.js) и отдаёт его в рейтинг.учестьПартию. Здесь ровно
   этот путь: собираем комнату с итогом партии, берём НАСТОЯЩЕЕ застолье
   из комнаты (а не собранное руками) и смотрим, сколько очков легло.

   Сценарии:
     1) дурак вчетвером: трое победили, один проиграл → каждому
        победителю 10 за одного обыгранного;
     2) дурак парами: пара победила двух живых → по 20 (10 + 10), за
        напарника 0 (решение владельца 30.09 09:31);
     3) ЗА НАПАРНИКА РОВНО 0 ПРИ ПОБЕДЕ: пара людей обыграла двух лёгких
        ботов (они стоят 0) — весь итог и есть доля напарника;
     4) ЗА НАПАРНИКА РОВНО 0 ПРИ НИЧЬЕЙ: все четверо вничью → по 5 + 5;
     5) ПРИ ПОРАЖЕНИИ: шесть проигранных вместе партий не съедают зачёт
        пары — потом один на один победа приносит полную цену;
     6) шашки вдвоём вничью → по 5;
     7) дурак: один победил, трое проиграли → 30.
   Застолье обязано вернуть строку на каждого сидящего и, в игре парами,
   номер напарника: пустое застолье — провал, а не пропуск.

   УМЕЕТ КРАСНЕТЬ:
     node tests/рейтинг-через-комнату.js --сломать
   копирует server/ (без server/данные) и js/игры-реестр.js во временную
   папку системы, в КОПИИ server/рейтинг.js возвращает старое правило
   (за напарника половина цены, через ограничитель сговора) и гоняет те же
   проверки на копии — прогон обязан провалиться. server/комнаты.js
   читается из проекта (он только собирает застолье), очки считает копия.
   Файлы проекта не трогаются.

   Запуск: node tests/рейтинг-через-комнату.js
   Выход 0 — провалов нет.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');

const ПРОЕКТ = path.join(__dirname, '..');
const гдеЛомать = process.argv.indexOf('--сломать');
const ЛОМАТЬ = гдеЛомать !== -1;

let всегоПроверок = 0;
let ошибок = 0;

function равно(что, было, надо) {
  всегоПроверок++;
  const ок = было === надо;
  if (!ок) ошибок++;
  console.log((ок ? '  ✓' : '  ✗') + ' ' + что + ': ' + было + (ок ? '' : ' (ждали ' + надо + ')'));
}

/** Заменить ровно одно вхождение, иначе приём порчи устарел — сказать вслух. */
function заменитьРовноОдин(файл, старое, новое) {
  const части = fs.readFileSync(файл, 'utf8').split(старое);
  if (части.length !== 2) {
    throw new Error('приём порчи устарел: «' + старое + '» встречается в ' + файл + ' ' +
      (части.length - 1) + ' раз(а) вместо одного — поправьте проверку тем же коммитом');
  }
  fs.writeFileSync(файл, части.join(новое), 'utf8');
}

/* Старое правило (до 30.09) словами кода: напарник проходит ограничитель
   сговора и приносит половину цены. Вставляется в КОПИЮ вместо пропуска. */
const СТАРОЕ_ПРАВИЛО_НАПАРНИКА =
  'if (этоНапарник) {\n' +
  '        /* ИСПОРЧЕНО --сломать: за напарника снова половина цены, как до 30.09 */\n' +
  '        if (параЕщёВЗачёте(запись, другой.номер, сегодня)) {\n' +
  "          const заНапарника = начислить(запись, 'человек', Math.floor(ценаСоперника(другой, исход) * 0.5), сегодня);\n" +
  '          добавлено[игрок.номер] += заНапарника;\n' +
  '          if (половина) половина.очки += заНапарника;\n' +
  '          половинаСостава.очки += заНапарника;\n' +
  '        }\n' +
  '        continue;\n' +
  '      }';

/** Откуда брать рейтинг: из проекта или из испорченной копии во временной папке. */
function кодИзКопииИлиПроекта() {
  if (!ЛОМАТЬ) return ПРОЕКТ;
  const аргумент = process.argv[гдеЛомать + 1];
  if (аргумент && аргумент.indexOf('--') !== 0) {
    console.error('ОШИБКА: после --сломать не допускаются аргументы; копия создаётся во временной папке');
    process.exit(2);
  }
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'рейтинг-через-комнату-сломать-'));
  // Боевые данные в копию не везём — они не нужны и не наши.
  fs.cpSync(path.join(ПРОЕКТ, 'server'), path.join(папка, 'server'), {
    recursive: true,
    filter: function (откуда) {
      const имя = path.basename(откуда);
      return имя !== 'данные' && имя !== 'node_modules';
    }
  });
  fs.mkdirSync(path.join(папка, 'js'), { recursive: true });
  fs.copyFileSync(path.join(ПРОЕКТ, 'js', 'игры-реестр.js'), path.join(папка, 'js', 'игры-реестр.js'));
  заменитьРовноОдин(path.join(папка, 'server', 'рейтинг.js'), 'if (этоНапарник) continue;', СТАРОЕ_ПРАВИЛО_НАПАРНИКА);
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: код из испорченной копии ' + папка + ' — прогон обязан провалиться ***\n');
  return папка;
}

const КОД = кодИзКопииИлиПроекта();
// Папку данных уводим ДО подключения комнат: они подключают рейтинг проекта сами.
process.env.GAMES_DATA = fs.mkdtempSync(path.join(os.tmpdir(), 'рейтинг-через-комнату-данные-'));
const рейтинг = require(path.join(КОД, 'server', 'рейтинг.js'));
const комнаты = require(path.join(ПРОЕКТ, 'server', 'комнаты.js'));
// Имена мест — из того же файла, что раздаёт их комнатам, а не своей копией.
const МЕСТА = require(path.join(ПРОЕКТ, 'server', 'партия-по-сети.js')).МЕСТА;
const ЗА_ЧЕЛОВЕКА = рейтинг.ЦЕНА.человек;

function человек(номер) { return { телеграм: номер, имя: 'П' + номер, этоБот: false }; }
function бот(уровень) { return { телеграм: null, имя: 'Бот', этоБот: true, уровень: уровень }; }

/**
 * Комната с кончившейся партией — в тех полях, что читает застольеДляРейтинга.
 * сидят — по местам по порядку; проигравшие — номера мест (с нуля).
 */
function комнатаСИтогом(игра, сидят, настройки) {
  const места = МЕСТА.slice(0, сидят.length);
  const игроки = {};
  места.forEach(function (место, и) {
    игроки[место] = Object.assign({ сдался: false }, сидят[и]);
  });
  const парами = настройки.парами === true;
  return {
    игра: игра, мест: места.length, парами: парами, переводной: false, уровеньБотов: 'обычный',
    игроки: игроки,
    партия: {
      завершена: true,
      ничья: настройки.ничья === true,
      проигравшие: (настройки.проигравшие || []).map(function (и) { return места[и]; }),
      игроки: места.slice(),
      парами: парами
    }
  };
}

/** Настоящее застолье комнаты; пустое или неполное — провал вслух. */
function застольеКомнаты(комната, ждёмНапарников) {
  const застолье = комнаты.застольеДляРейтинга(комната);
  равно('   застолье: строк столько же, сколько сидит', застолье.length, Object.keys(комната.игроки).length);
  if (ждёмНапарников) {
    // Напарник — через место (0↔2, 1↔3): у людей обязан прийти номер напарника.
    const людиСНапарником = застолье.filter(function (строка, и) {
      const напарник = застолье[(и + 2) % застолье.length];
      return строка.номер && напарник.номер && строка.напарник === напарник.номер;
    }).length;
    const людиСНапарникомЧеловеком = застолье.filter(function (строка, и) {
      return строка.номер && застолье[(и + 2) % застолье.length].номер;
    }).length;
    равно('   застолье: у каждого человека с напарником-человеком номер напарника на месте',
      людиСНапарником > 0 && людиСНапарником === людиСНапарникомЧеловеком, true);
  }
  return застолье;
}

function очки(номер, игра) {
  const срез = рейтинг.срезДляИгрока(игра || 'дурак', номер);
  return срез.я ? срез.я.очки : 0;
}

