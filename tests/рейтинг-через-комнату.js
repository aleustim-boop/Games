const fs = require('fs');
const os = require('os');
const path = require('path');

const ПРОЕКТ = path.join(__dirname, '..');
const гдеЛомать = process.argv.indexOf('--сломать');
const ЛОМАТЬ = гдеЛомать !== -1;

let всегоПроверок = 0;
let ошибок = 0;

function равно(что, было, надо) {
  всегоПроверок++;
  const ок = было === надо;
  if (!ок) ошибок++;
  console.log((ок ? '  ✓' : '  ✗') + ' ' + что + ': ' + было + (ок ? '' : ' (ждали ' + надо + ')'));
}

/** Заменить ровно одно вхождение, иначе приём порчи устарел — сказать вслух. */
function заменитьРовноОдин(файл, старое, новое) {
  const части = fs.readFileSync(файл, 'utf8').split(старое);
  if (части.length !== 2) {
    throw new Error('приём порчи устарел: «' + старое + '» встречается в ' + файл + ' ' +
      (части.length - 1) + ' раз(а) вместо одного — поправьте проверку тем же коммитом');
  }
  fs.writeFileSync(файл, части.join(новое), 'utf8');
}

/** Откуда брать код: из проекта или из испорченной копии. */
function кодИзКопииИлиПроекта() {
  if (!ЛОМАТЬ) return ПРОЕКТ;
  const аргумент = process.argv[гдеЛомать + 1];
  // Проверяем, что после --сломать нет лишних аргументов
  if (аргумент && аргумент.indexOf('--') !== 0) {
    console.error('ОШИБКА: после --сломать не допускаются аргументы; копия создаётся во временной папке');
    process.exit(2);
  }
  // Копия ВСЕГДА во временной папке
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'рейтинг-через-комнату-сломать-'));
  fs.mkdirSync(папка, { recursive: true });
  // Боевые данные в копию не везём — они не нужны и не наши.
  fs.cpSync(path.join(ПРОЕКТ, 'server'), path.join(папка, 'server'), {
    recursive: true,
    filter: function (откуда) {
      const имя = path.basename(откуда);
      return имя !== 'данные' && имя !== 'node_modules';
    }
  });
  fs.mkdirSync(path.join(папка, 'js'), { recursive: true });
  fs.copyFileSync(path.join(ПРОЕКТ, 'js', 'игры-реестр.js'), path.join(папка, 'js', 'игры-реестр.js'));
  // Порча: убираем проверку напарников в учестьПартию
  заменитьРовноОдин(path.join(папка, 'server', 'рейтинг.js'),
    '(этоНапарник ? 0.5 : 1)',
    '1 /* ИСПОРЧЕНО --сломать: нет множителя за напарников */');
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: код из испорченной копии ' + папка + ' — прогон обязан провалиться ***\n');
  return папка;
}

const КОД = кодИзКопииИлиПроекта();
process.env.GAMES_DATA = fs.mkdtempSync(path.join(os.tmpdir(), 'рейтинг-через-комнату-данные-'));
const рейтинг = require(path.join(КОД, 'server', 'рейтинг.js'));

console.log('=== Рейтинг: учёты через застолье комнаты (как в комнатах.js) ===\n');

/** Участник в формате, который возвращает застольеДляРейтинга. */
function участник(номер, имя, победил, ничья, напарник, этоБот) {
  return {
    номер: номер,
    имя: имя || ('П' + номер),
    этоБот: этоБот || false,
    победил: победил || false,
    ничья: ничья || false,
    напарник: напарник || null,
    парами: напарник !== null && напарник !== undefined,
    переводной: false,
    уровень: этоБот ? 'средний' : undefined
  };
}

function очки(номер, игра) {
  const срез = рейтинг.срезДляИгрока(игра || 'дурак', номер);
  return срез.я ? срез.я.очки : 0;
}

console.log('1. Дурак вчетвером: один проиграл (место 0), трое (1,2,3) победили');
console.log('   Каждый победитель → за одного обыгранного (проигравшего)');
рейтинг.забытьВсё();
рейтинг.учестьПартию('дурак', [
  участник(101, 'А', false, false),  // место 0: проиграл
  участник(102, 'Б', true, false),   // место 1: победил
  участник(103, 'В', true, false),   // место 2: победил
  участник(104, 'Г', true, false)    // место 3: победил
]);
равно('102 (победитель): 10 за одного обыгранного', очки(102), 10);
равно('103 (победитель): 10 за одного обыгранного', очки(103), 10);
равно('104 (победитель): 10 за одного обыгранного', очки(104), 10);
равно('101 (проигравший): 0', очки(101), 0);

console.log('\n2. Дурак вчетвером парами: (201, 203) победили vs (202, 204) проиграли');
console.log('   Победитель с напарником → 10 за каждого соперника + 5 за напарника');
рейтинг.забытьВсё();
рейтинг.учестьПартию('дурак', [
  участник(201, 'А', true, false, 203),    // место 0: победил, напарник 203
  участник(202, 'Б', false, false, 204),   // место 1: проиграл, напарник 204
  участник(203, 'В', true, false, 201),    // место 2: победил, напарник 201
  участник(204, 'Г', false, false, 202)    // место 3: проиграл, напарник 202
]);
равно('201 (победитель с напарником): 10+10+5 = 25', очки(201), 25);
равно('203 (победитель с напарником): 10+10+5 = 25', очки(203), 25);
равно('202 (проигравший): 0', очки(202), 0);
равно('204 (проигравший): 0', очки(204), 0);

console.log('\n3. Шашки вдвоём: обе ничья');
console.log('   Ничейник → за одного соперника (5 очков)');
рейтинг.забытьВсё();
рейтинг.учестьПартию('шашки', [
  участник(301, 'А', false, true),
  участник(302, 'Б', false, true)
]);
равно('301 (ничья): 5', очки(301, 'шашки'), 5);
равно('302 (ничья): 5', очки(302, 'шашки'), 5);

console.log('\n4. Дурак: один победил, трое проиграли');
console.log('   Победитель один → за трёх соперников (только обыгранных) = 3×10');
рейтинг.забытьВсё();
рейтинг.учестьПартию('дурак', [
  участник(401, 'А', true, false),   // место 0: победил
  участник(402, 'Б', false, false),  // место 1: проиграл
  участник(403, 'В', false, false),  // место 2: проиграл
  участник(404, 'Г', false, false)   // место 3: проиграл
]);
равно('401 (единственный победитель): 30 за троих обыгранных', очки(401), 30);
равно('402, 403, 404 (проигравшие): по 0', очки(402) === 0 && очки(403) === 0 && очки(404) === 0, true);

console.log('\n----------------------------------------');
console.log('Итого проверок: ' + всегоПроверок + ', провалов: ' + ошибок);
process.exit(ошибок ? 1 : 0);
