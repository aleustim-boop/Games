/* =====================================================================
   ВХОД ПО ПРИГЛАШЕНИЮ — В САМИ ШАШКИ.

   Что поменяли и почему это надо проверить отдельно. Переход «витрина →
   Шашки» теперь несёт с собой ТОЛЬКО адрес сервера и признак приглашения,
   а код комнаты и стартовый параметр Telegram остаются у дурака: раньше
   человек, пришедший по приглашению в дурака, нажимал «Шашки» — и шашки
   лезли в комнату дурака.

   Но у приглашения есть и вторая дорога, обратная: ссылка САМА адресована
   шашкам («shashki_КОД»). Тогда код — их собственный, и потерять его
   нельзя: человек попадёт в меню вместо стола, за которым его ждут.
   Эта дорога идёт через настоящий браузер, потому что в ней участвуют
   две страницы (index.html сама себя заменяет на шашки.html) и живой
   Telegram-параметр запуска.

   Что проверяется:
     1. приглашение приехало стартовым параметром Telegram
        («shashki_КОД») — человек оказывается ЗА СТОЛОМ ШАШЕК,
        а хозяин стола видит, что друг пришёл;
     2. то же самое, но приглашение приехало решёткой адреса
        («#tgWebAppStartParam=shashki_КОД») — так открывается вне Telegram;
     3. приглашение в ДУРАКА, человек жмёт «Шашки»: чужой код с ним
        не едет, и шашки показывают своё меню, а не чужую комнату;
     4. приглашение в шашки, а в памяти браузера лежит вчерашний мёртвый
        адрес: играем по адресу из ссылки, а не по мёртвому.

   Что нужно поднять заранее:
       node server/сервер.js 8817 --без-памяти     (живой сервер комнат)
       страничный сервер на 8080 (его держит штаб)

   Запуск:
       node tests/приглашение-в-шашки.js 8080 8817
   ===================================================================== */

const http = require('http');
const path = require('path');
const { chromium, подготовитьПодделку } = require('./браузер-робот.js');

const ПОРТ_СТРАНИЦ = Number(process.argv[2]) || 8080;
const ПОРТ_КОМНАТ = Number(process.argv[3]) || 8817;
const ПОРТ_МЁРТВОГО = 8899;

const САЙТ = 'http://127.0.0.1:' + ПОРТ_СТРАНИЦ;
const ЖИВОЙ = 'http://127.0.0.1:' + ПОРТ_КОМНАТ;
const МЁРТВЫЙ = 'http://127.0.0.1:' + ПОРТ_МЁРТВОГО;
/* Ключ адреса переехал на латиницу (в облаке Telegram русские имена
   не записываются). Кладём под старым именем — как в телефоне живого
   игрока, пришедшего с прошлой версии, — а читаем под новым: туда игра
   пишет теперь. */
const КЛЮЧ_АДРЕСА = 'server_address';
const ПАПКА_СНИМКОВ = path.join(__dirname, 'скриншоты');

let провалов = 0;
function проверить(условие, слова) {
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}
function сказать(слова) { console.log('  ' + слова); }
const спать = (мс) => new Promise((ф) => setTimeout(ф, мс));

/** Обычный запрос к серверу комнат — как со второго телефона. */
function зов(путь, тело) {
  return new Promise(function (готово) {
    const текст = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const о = http.request({
      host: '127.0.0.1', port: ПОРТ_КОМНАТ, method: 'POST', path: encodeURI(путь),
      headers: { 'Content-Type': 'application/json', 'Content-Length': текст.length }
    }, function (ответ) {
      let к = '';
      ответ.on('data', (ч) => { к += ч; });
      ответ.on('end', function () { try { готово(JSON.parse(к)); } catch (сбой) { готово(null); } });
    });
    о.on('error', () => готово(null));
    о.end(текст);
  });
}

/** Завести стол и вернуть код с пропуском хозяина. */
async function завестиСтол(игра) {
  const с = await зов('/создать', игра === 'шашки' ? { игра: 'шашки' } : {});
  if (!с || !с.код) throw new Error('сервер комнат не дал создать стол ' + игра);
  /* Убеждаемся, что на свежем столе друга ЕЩЁ НЕТ. Без этого проверка
     «друг пришёл» могла бы зеленеть сама по себе, ничего не поймав. */
  if (с.состояние && с.состояние.соперникПришёл === true) {
    throw new Error('на только что созданном столе сервер уже говорит «друг пришёл» — ' +
      'проверять приход друга по этому полю нельзя');
  }
  return { код: с.код, пропуск: с.пропуск };
}

/**
 * Пришёл ли к хозяину друг.
 *
 * Спрашиваем сам сервер и только про одно поле — «соперникПришёл».
 * Оно у свежесозданного стола заведомо «нет» (это проверяется отдельно,
 * в «завестиСтол»), поэтому «да» здесь означает ровно то, что написано,
 * и проверка не может позеленеть сама по себе.
 */
async function дождатьсяДруга(стол, потолокМс) {
  const начало = Date.now();
  while (Date.now() - начало < (потолокМс || 15000)) {
    const с = await зов('/состояние', { код: стол.код, пропуск: стол.пропуск });
    const вид = с && с.состояние;
    if (вид && вид.соперникПришёл === true) return Date.now() - начало;
    await спать(200);
  }
  return -1;
}

/** Что лежит в памяти браузера под адресом сервера. */
function памятьСтраницы(страница) {
  return страница.evaluate(function (ключ) {
    try { return window.localStorage.getItem(ключ) || ''; } catch (сбой) { return '(память запрещена)'; }
  }, КЛЮЧ_АДРЕСА);
}

/**
 * Дождаться, пока память успокоится: значение не меняется три замера
 * подряд. По часам ждать нельзя — стук в оба адреса идёт своим сроком,
 * и мерка попала бы в середину разговора с сервером.
 */
async function дождатьсяПокояПамяти(страница, потолокМс) {
  const начало = Date.now();
  let прежнее = await памятьСтраницы(страница);
  let одинаковых = 0;
  while (Date.now() - начало < (потолокМс || 10000)) {
    await спать(150);
    const сейчас = await памятьСтраницы(страница);
    if (сейчас === прежнее) {
      одинаковых++;
      if (одинаковых >= 3) break;
    } else { одинаковых = 0; прежнее = сейчас; }
  }
  return прежнее;
}

/** Дождаться, пока на странице покажется хоть один экран. */
async function дождатьсяЭкрана(страница, потолокМс) {
  const начало = Date.now();
  while (Date.now() - начало < (потолокМс || 8000)) {
    const имя = await какойЭкран(страница).catch(function () { return '(ни одного)'; });
    if (имя && имя !== '(ни одного)') return имя;
    await спать(50);
  }
  return '(ни одного)';
}

/* ------------------------------------------------------------------
   Браузер
   ------------------------------------------------------------------ */

async function завестиЗаход(браузер, настройки) {
  const окно = await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
  const память = настройки.память || '';
  await окно.addInitScript(function (что) {
    try {
      if (window.localStorage.getItem('стенд:посеяно')) return;
      window.localStorage.setItem('стенд:посеяно', 'да');
      if (что) window.localStorage.setItem('подкидной-дурак:адрес-сервера', что);
    } catch (сбой) { /* памяти нет — заход всё равно что-то покажет */ }
  }, память);

  const страница = await окно.newPage();
  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', function (м) {
    if (м.type() === 'error') красные.push('консоль: ' + м.text());
  });
  await подготовитьПодделку(страница, {
    версия: '7.10',
    стартовыйПараметр: настройки.стартовыйПараметр || ''
  });
  return { окно, страница, красные };
}

/** Куда привёл адрес страницы (уже раскодированный). */
function куда(страница) {
  let адрес = страница.url();
  try { адрес = decodeURIComponent(адрес); } catch (сбой) { /* и так сойдёт */ }
  return адрес;
}

async function дождатьсяСтраницы(страница, примета, потолокМс) {
  const начало = Date.now();
  while (Date.now() - начало < (потолокМс || 10000)) {
    if (куда(страница).indexOf(примета) !== -1) return Date.now() - начало;
    await спать(50);
  }
  return -1;
}

function видно(страница, примета) {
  return страница.evaluate(function (имя) {
    const узел = document.getElementById(имя);
    if (!узел) return false;
    const место = узел.getBoundingClientRect();
    if (место.width < 1 || место.height < 1) return false;
    const вид = window.getComputedStyle(узел);
    return вид.display !== 'none' && вид.visibility !== 'hidden';
  }, примета);
}

async function ждатьВидимости(страница, примета, потолокМс) {
  const начало = Date.now();
  while (Date.now() - начало < (потолокМс || 10000)) {
    if (await видно(страница, примета)) return Date.now() - начало;
    await спать(50);
  }
  return -1;
}

/** Какой экран сейчас на виду. */
function какойЭкран(страница) {
  return страница.evaluate(function () {
    const виден = document.querySelector('.экран--виден');
    return виден ? виден.id : '(ни одного)';
  });
}

/* ------------------------------------------------------------------ */

(async () => {
  console.log('Вход по приглашению — в сами шашки. Страницы: ' + ПОРТ_СТРАНИЦ +
    ', комнаты: ' + ПОРТ_КОМНАТ + '.');

  const здоровье = await зов('/состояние', { код: 'нет', пропуск: 'нет' });
  проверить(здоровье !== null, 'сервер комнат отвечает (' + ПОРТ_КОМНАТ + ')');
  if (здоровье === null) {
    console.log('\nСтенд не готов: сервер комнат не поднят.');
    process.exit(2);
  }

  const браузер = await chromium.launch();
  const всеКрасные = [];

  /* ===== 1. Приглашение в шашки приехало стартовым параметром Telegram ==== */
  console.log('\n1. Приглашение «shashki_КОД» приехало параметром запуска Telegram');
  {
    const стол = await завестиСтол('шашки');
    сказать('хозяин завёл стол шашек, код ' + стол.код);
    const з = await завестиЗаход(браузер, { стартовыйПараметр: 'shashki_' + стол.код });
    await з.страница.goto(САЙТ + '/index.html?сервер=' + ЖИВОЙ, { waitUntil: 'domcontentloaded' });

    const доШашек = await дождатьсяСтраницы(з.страница, 'шашки.html', 10000);
    проверить(доШашек >= 0, 'игра сама увела на страницу шашек (' + доШашек + ' мс)');
    сказать('адрес: ' + куда(з.страница));

    const пришёл = await дождатьсяДруга(стол, 15000);
    проверить(пришёл >= 0, 'хозяин стола видит, что друг пришёл (' + пришёл + ' мс)');
    const доДоски = await ждатьВидимости(з.страница, 'доска', 15000);
    проверить(доДоски >= 0, 'у пришедшего открылась доска шашек (' + доДоски + ' мс)');
    if (доДоски < 0) сказать('на виду экран: ' + (await какойЭкран(з.страница)));
    await з.страница.screenshot({ path: path.join(ПАПКА_СНИМКОВ, 'приглашение-в-шашки.png') });

    всеКрасные.push(...з.красные.map((с) => '[заход 1] ' + с));
    await з.окно.close();
  }

  /* ===== 2. То же приглашение, но решёткой адреса (вне Telegram) ========== */
  console.log('\n2. То же приглашение решёткой адреса (#tgWebAppStartParam=shashki_КОД)');
  {
    const стол = await завестиСтол('шашки');
    const з = await завестиЗаход(браузер, {});
    await з.страница.goto(САЙТ + '/index.html?сервер=' + ЖИВОЙ +
      '#tgWebAppStartParam=shashki_' + стол.код, { waitUntil: 'domcontentloaded' });

    const доШашек = await дождатьсяСтраницы(з.страница, 'шашки.html', 10000);
    проверить(доШашек >= 0, 'игра сама увела на страницу шашек (' + доШашек + ' мс)');
    сказать('адрес: ' + куда(з.страница));
    const пришёл = await дождатьсяДруга(стол, 15000);
    проверить(пришёл >= 0, 'хозяин стола видит, что друг пришёл (' + пришёл + ' мс)');
    const доДоски = await ждатьВидимости(з.страница, 'доска', 15000);
    проверить(доДоски >= 0, 'у пришедшего открылась доска шашек (' + доДоски + ' мс)');
    if (доДоски < 0) сказать('на виду экран: ' + (await какойЭкран(з.страница)));

    всеКрасные.push(...з.красные.map((с) => '[заход 2] ' + с));
    await з.окно.close();
  }

  /* ===== 3. Приглашение в ДУРАКА, а человек уходит в шашки ================ */
  console.log('\n3. Приглашение в дурака, человек жмёт «Шашки»: чужой код с ним ехать не должен');
  {
    const стол = await завестиСтол('дурак');
    сказать('хозяин завёл стол ДУРАКА, код ' + стол.код);
    const з = await завестиЗаход(браузер, { стартовыйПараметр: 'durak_' + стол.код });
    await з.страница.goto(САЙТ + '/index.html?сервер=' + ЖИВОЙ, { waitUntil: 'domcontentloaded' });

    // Дурак сам входит в комнату по приглашению — дождёмся, чтобы было что терять.
    const пришёл = await дождатьсяДруга(стол, 15000);
    проверить(пришёл >= 0, 'в дурака по приглашению человек за стол сел (' + пришёл + ' мс)');

    // Теперь — на витрину и в шашки, как человек.
    /* «К выбору игры» с 11 сентября — стрелка «‹» в верхней строке лобби
       дурака (прежнего меню с #кнопка-меню-назад нет). Приглашение уводит
       человека дальше, поэтому сперва возвращаемся в лобби его же дверью,
       а потом жмём «‹» как человек, если строка видна (в Telegram её прячут —
       тогда витрину откроем ниже тем же способом, что и игра). */
    await з.страница.evaluate(function () {
      if (typeof показатьЛоббиДурака === 'function') показатьЛоббиДурака();
    });
    const стрелкаЛобби = з.страница.locator('#экран-лобби [data-путь="назад"]');
    if (await стрелкаЛобби.count() && await стрелкаЛобби.first().isVisible()) {
      await стрелкаЛобби.first().click();
    }
    const естьПлитка = await ждатьВидимости(з.страница, 'кнопка-игра-шашки', 8000);
    if (естьПлитка < 0) {
      // Витрина не показалась сама — откроем её тем же способом, что и игра.
      await з.страница.evaluate(function () {
        if (typeof показатьЭкран === 'function') показатьЭкран('экран-витрины');
      });
    }
    await ждатьВидимости(з.страница, 'кнопка-игра-шашки', 8000);
    await з.страница.click('#кнопка-игра-шашки');
    const доШашек = await дождатьсяСтраницы(з.страница, 'шашки.html', 10000);
    проверить(доШашек >= 0, 'страница шашек открылась (' + доШашек + ' мс)');
    const адрес = куда(з.страница);
    сказать('адрес: ' + адрес);
    проверить(адрес.indexOf('код=') === -1 && адрес.indexOf('code=') === -1,
      'чужой код комнаты в адрес шашек не уехал');
    проверить(адрес.indexOf('tgWebAppStartParam') === -1,
      'стартовый параметр Telegram в адрес шашек не уехал');
    проверить(адрес.indexOf('сервер=') !== -1, 'адрес сервера в шашки поехал (он им нужен)');
    /* Ждём, пока страница шашек нарисует хоть один экран: сразу после
       перехода их не видно ни одного, и мерка успела бы прочитать пустоту. */
    const экран = await дождатьсяЭкрана(з.страница, 8000);
    сказать('на виду экран: ' + экран);
    проверить(экран === 'экран-режимов', 'шашки показали своё меню, а не чужую комнату');

    всеКрасные.push(...з.красные.map((с) => '[заход 3] ' + с));
    await з.окно.close();
  }

  /* ===== 4. Приглашение в шашки при мёртвом адресе в памяти =============== */
  console.log('\n4. Приглашение в шашки, а в памяти вчерашний мёртвый адрес');
  {
    const стол = await завестиСтол('шашки');
    const з = await завестиЗаход(браузер, {
      память: МЁРТВЫЙ, стартовыйПараметр: 'shashki_' + стол.код
    });
    await з.страница.goto(САЙТ + '/index.html?сервер=' + ЖИВОЙ, { waitUntil: 'domcontentloaded' });
    const доШашек = await дождатьсяСтраницы(з.страница, 'шашки.html', 10000);
    проверить(доШашек >= 0, 'игра сама увела на страницу шашек (' + доШашек + ' мс)');
    const пришёл = await дождатьсяДруга(стол, 20000);
    проверить(пришёл >= 0, 'друг сел за стол на ЖИВОМ сервере, а не в мёртвый адрес (' + пришёл + ' мс)');
    /* И ещё одно, ради чего вчера чинили адреса: мёртвый адрес в памяти
       должен смениться живым, пришедшим ссылкой. Ждём ПОКОЯ, а не
       миллисекунд: стук в оба адреса идёт своим сроком. */
    const память = await дождатьсяПокояПамяти(з.страница, 10000);
    сказать('в памяти теперь: ' + память);
    проверить(память === ЖИВОЙ,
      'вчерашний мёртвый адрес в памяти заменён живым из ссылки');

    всеКрасные.push(...з.красные.map((с) => '[заход 4] ' + с));
    await з.окно.close();
  }

  await браузер.close();

  console.log('\nКрасных строк в консоли: ' + всеКрасные.length);
  for (const строка of всеКрасные) console.log('   ' + строка);
  console.log('Провалов: ' + провалов);
  process.exit(провалов > 0 ? 1 : 0);
})().catch(function (сбой) {
  console.error('Стенд упал: ' + (сбой && сбой.stack ? сбой.stack : сбой));
  process.exit(2);
});
