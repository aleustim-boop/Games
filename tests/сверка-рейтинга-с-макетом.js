function запрещённыйАдрес(адрес) {
  const низ = адрес.toLowerCase();
  if (низ.indexOf('.env') !== -1) return true;
  const части = низ.split('/').filter(Boolean);
  if (части[0] === 'bot') return true;
  return части.some((ч) => ч.charAt(0) === '.');
}

function поднятьСервер(порт, копии) {
  return new Promise((готово) => {
    const сервер = http.createServer((запрос, ответ) => {
      let адрес;
      try { адрес = decodeURIComponent(запрос.url.split('?')[0]); } catch (о) { ответ.writeHead(400); ответ.end(); return; }
      if (адрес === '/') адрес = '/index.html';
      if (запрещённыйАдрес(адрес)) { ответ.writeHead(403); ответ.end(); return; }
      let корень = КОРЕНЬ;
      let хвост = адрес;
      if (адрес.indexOf('/макет/') === 0) { корень = path.resolve(КОМПЛЕКТ); хвост = адрес.slice('/макет'.length); }
      const файл = path.join(корень, хвост.replace(/^\/+/, ''));
      if (!файл.startsWith(корень + path.sep)) { ответ.writeHead(403); ответ.end(); return; }
      const заголовки = { 'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'application/octet-stream', 'Cache-Control': 'no-store' };
      if (Object.prototype.hasOwnProperty.call(копии, файл)) { ответ.writeHead(200, заголовки); ответ.end(копии[файл]); return; }
      fs.readFile(файл, (ошибка, данные) => {
        if (ошибка) { ответ.writeHead(404); ответ.end('нет: ' + адрес); return; }
        ответ.writeHead(200, заголовки);
        ответ.end(данные);
      });
    });
    сервер.listen(порт, ХОЗЯИН, () => готово(сервер));
  });
}

function свободныйПорт() {
  return new Promise((готово, брак) => {
    const проба = http.createServer();
    проба.on('error', брак);
    проба.listen(0, ХОЗЯИН, () => { const п = проба.address().port; проба.close(() => готово(п)); });
  });
}

async function выбратьПорт() {
  for (let и = 0; и < 6; и++) {
    const п = await свободныйПорт();
    if (ЗАПРЕЩЁННЫЕ_ПОРТЫ.indexOf(п) === -1) return п;
  }
  throw new Error('не нашёлся свободный порт');
}

