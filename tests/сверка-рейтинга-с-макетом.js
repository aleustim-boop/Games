/** Рейтинг так же, как его считает prototype/app.js (ranking): сумма очков
    по активным играм или очки одной игры, при равенстве — по id. */
function рейтингМакета(игра, толькоДрузья, кругДрузей) {
  const люди = ДЕМО.players.filter((ч) => !толькоДрузья || кругДрузей(ч) || ч.id === ДЕМО.currentUserId);
  return люди.map((ч) => ({
    id: ч.id,
    имя: ч.name,
    очки: игра === 'all' ? АКТИВНЫЕ.reduce((с, и) => с + (ч.points[и.id] || 0), 0) : (ч.points[игра] || 0)
  })).sort((а, б) => б.очки - а.очки || а.id.localeCompare(б.id));
}

/** Движение места — то же правило, что delta() в prototype/app.js. */
function движениеМакета(ч, игра) {
  const n = ч.id === 'alexey' ? (игра === 'all' ? 12 : 5) : (ч.очки % 4);
  return n ? { движение: 'выросло', сдвиг: n } : { движение: 'безИзменений', сдвиг: 0 };
}

function строкаОтвета(ч, место, игра) {
  const д = движениеМакета(ч, игра);
  return {
    место: место, имя: ч.имя, очки: ч.очки,
    побед: 1, партий: 1,
    этоЯ: ч.id === ДЕМО.currentUserId,
    движение: д.движение, сдвиг: д.сдвиг
  };
}

/** Срез ответа двери /рейтинг: верхушка 20 строк (как limit в макете)
    и окно «трое выше — я — трое ниже». */
function срезОтвета(ряды, игра) {
  const строки = ряды.map((ч, и) => строкаОтвета(ч, и + 1, игра));
  const мой = строки.findIndex((с) => с.этоЯ);
  return {
    верхушка: строки.slice(0, 20),
    вокругМеня: мой === -1 ? [] : строки.slice(Math.max(0, мой - 3), мой + 4),
    всего: строки.length,
    я: мой === -1 ? null : строки[мой]
  };
}

/* Круг друзей: обычный — как в demo-data.js (поле isFriend); «двое» —
   только MaxPlay, чтобы с Алексеем на подиуме оказалось два человека. */
const ДРУЗЬЯ_ОБЫЧНО = (ч) => ч.isFriend;
const ДРУЗЬЯ_ДВОЕ = (ч) => ч.id === 'max';

function ответДвериРейтинга(нашаИгра, набор) {
  const игра = КЛЮЧ_МАКЕТА[нашаИгра] || 'all';
  /* «пусто-шахматы»: в Шахматах никто не играл — пустой срез, как отдаёт
     сервер для игры без партий. Остальные игры — обычные. */
  if (набор === 'пусто-шахматы' && нашаИгра === 'шахматы') {
    return {
      ок: true, узналиВас: true, игра: нашаИгра, всего: 0, яВТаблице: false, я: null,
      верхушка: [], вокругМеня: [], сила: null,
      друзья: { естьДрузья: true, всего: 0, яВТаблице: false, я: null, верхушка: [], вокругМеня: [] }
    };
  }
  /* «двое-все»: во всей таблице только MaxPlay и я — случай владельца
     с большого экрана (рейтинг Дурака, подиум из двух). */
  const общий = набор === 'двое-все'
    ? срезОтвета(рейтингМакета(игра, true, ДРУЗЬЯ_ДВОЕ), игра)
    : срезОтвета(рейтингМакета(игра, false), игра);
  const друзья = срезОтвета(рейтингМакета(игра, true, набор && набор.indexOf('двое') === 0 ? ДРУЗЬЯ_ДВОЕ : ДРУЗЬЯ_ОБЫЧНО), игра);
  return {
    ок: true, узналиВас: true, игра: нашаИгра,
    всего: общий.всего, яВТаблице: true, я: общий.я,
    верхушка: общий.верхушка, вокругМеня: общий.вокругМеня, сила: null,
    /* Поля среза друзей — те же, что собирает server/сервер.js (друзья: {…}). */
    друзья: {
      естьДрузья: true, всего: друзья.всего, яВТаблице: Boolean(друзья.я), я: друзья.я,
      верхушка: друзья.верхушка, вокругМеня: друзья.вокругМеня
    }
  };
}

