/** Снять числа узлов на странице. Псевдоэлемент — через «::before» в хвосте селектора. */
async function снятьЧисла(страница, пары, сторона) {
  const запросы = пары.map((п) => ({ имя: п[0], селектор: сторона === 'макет' ? п[1] : п[2] }));
  return страница.evaluate((запросы) => {
    const итог = {};
    for (const з of запросы) {
      let селектор = з.селектор;
      let псевдо = null;
      const м = селектор.match(/::(before|after)$/);
      if (м) { псевдо = '::' + м[1]; селектор = селектор.slice(0, -м[0].length); }
      const узел = document.querySelector(селектор);
      if (!узел) { итог[з.имя] = null; continue; }
      const с = getComputedStyle(узел, псевдо);
      if (псевдо && (с.content === 'none' || с.content === 'normal')) { итог[з.имя] = null; continue; }
      const р = узел.getBoundingClientRect();
      итог[з.имя] = {
        шрифт: с.fontFamily.split(',')[0].replace(/["']/g, '').trim(),
        размер: с.fontSize, вес: с.fontWeight, строка: с.lineHeight, разрядка: с.letterSpacing,
        цвет: с.color, фон: с.backgroundColor,
        градиент: с.backgroundImage === 'none' ? 'none' : с.backgroundImage.slice(0, 90),
        рамка: с.borderTopWidth + ' ' + с.borderTopColor,
        радиус: с.borderTopLeftRadius,
        отступы: [с.paddingTop, с.paddingRight, с.paddingBottom, с.paddingLeft].join(' '),
        тень: с.boxShadow === 'none' ? 'none' : с.boxShadow.slice(0, 70),
        x: псевдо ? parseFloat(с.left) || 0 : Math.round(р.left),
        ш: псевдо ? Math.round(parseFloat(с.width) || 0) : Math.round(р.width),
        в: псевдо ? Math.round(parseFloat(с.height) || 0) : Math.round(р.height),
        текст: псевдо ? '' : (узел.textContent || '').replace(/\s+/g, ' ').trim().slice(0, 30)
      };
    }
    return итог;
  }, запросы);
}

/* ---------------------------------------------------------------------
   Сравнение. Цвета приводим к rgba-числам (у нас бывает color(srgb …)
   от color-mix), пиксели сравниваем с допуском 1px.
   --------------------------------------------------------------------- */

function цветВЧисла(значение) {
  let м = String(значение).match(/rgba?\(([\d.]+),\s*([\d.]+),\s*([\d.]+)(?:,\s*([\d.]+))?\)/);
  if (м) return [+м[1], +м[2], +м[3], м[4] === undefined ? 1 : +м[4]];
  м = String(значение).match(/color\(srgb\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)(?:\s*\/\s*([\d.]+))?\)/);
  if (м) return [+м[1] * 255, +м[2] * 255, +м[3] * 255, м[4] === undefined ? 1 : +м[4]];
  return null;
}

function цветКратко(значение) {
  const ч = цветВЧисла(значение);
  if (!ч) return значение;
  const hex = '#' + ч.slice(0, 3).map((к) => Math.round(к).toString(16).padStart(2, '0')).join('');
  return ч[3] >= 0.999 ? hex : hex + ' α' + (Math.round(ч[3] * 100) / 100);
}

function равныЦвета(а, б) {
  const ча = цветВЧисла(а), чб = цветВЧисла(б);
  if (!ча || !чб) return а === б;
  if (ча[3] < 0.01 && чб[3] < 0.01) return true;
  return ча.every((к, и) => Math.abs(к - чб[и]) <= (и === 3 ? 0.03 : 4));
}

function равныЧисла(а, б) {
  const ча = String(а).match(/-?[\d.]+/g), чб = String(б).match(/-?[\d.]+/g);
  if (!ча || !чб || ча.length !== чб.length) return String(а) === String(б);
  return ча.every((к, и) => Math.abs(parseFloat(к) - parseFloat(чб[и])) <= 1);
}

const СВОЙСТВА = [
  ['шрифт', 'строка'], ['размер', 'число'], ['вес', 'число'], ['строка', 'число'], ['разрядка', 'число'],
  ['цвет', 'цвет'], ['фон', 'цвет'], ['градиент', 'строка'], ['рамка', 'рамка'], ['радиус', 'число'],
  ['отступы', 'число'], ['x', 'число'], ['ш', 'число'], ['в', 'число']
];

function сравнить(числаМакета, числаНаши, пары) {
  const расхождения = [];
  for (const п of пары) {
    const имя = п[0];
    const м = числаМакета[имя], н = числаНаши[имя];
    if (!м && !н) continue;
    if (!м || !н) {
      расхождения.push({ узел: имя, свойство: 'узел', макет: м ? 'есть «' + м.текст + '»' : 'нет узла', наш: н ? 'есть «' + н.текст + '»' : 'нет узла' });
      continue;
    }
    for (const [свойство, род] of СВОЙСТВА) {
      let равно;
      if (род === 'цвет') равно = равныЦвета(м[свойство], н[свойство]);
      else if (род === 'число') равно = равныЧисла(м[свойство], н[свойство]);
      else if (род === 'рамка') {
        const шм = parseFloat(м.рамка), шн = parseFloat(н.рамка);
        равно = шм === 0 && шн === 0 ? true : Math.abs(шм - шн) <= 0.5 && равныЦвета(м.рамка.replace(/^\S+\s/, ''), н.рамка.replace(/^\S+\s/, ''));
      } else if (свойство === 'градиент') равно = (м.градиент === 'none') === (н.градиент === 'none');
      else равно = м[свойство] === н[свойство];
      if (!равно) {
        const показать = (з) => род === 'цвет' ? цветКратко(з) : род === 'рамка' ? з.replace(/(rgba?\([^)]*\)|color\([^)]*\))/, цветКратко) : з;
        расхождения.push({ узел: имя, свойство: свойство, макет: показать(м[свойство]), наш: показать(н[свойство]) });
      }
    }
  }
  return расхождения;
}

