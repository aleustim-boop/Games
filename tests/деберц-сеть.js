'use strict';
const assert = require('node:assert/strict');
const И = require('../server/игры/деберц.js');
const П = require('../js/деберц-правила.js');
const партия = И.раздать(null, { игроки: ['место-а', 'место-б'] });
function отказ(кто, намерение) {
  const раньше = JSON.stringify(партия);
  assert.equal(И.сделатьХод(партия, кто, намерение).принято, false);
  assert.equal(JSON.stringify(партия), раньше);
}
отказ('чужой', { действие: 'сдаться' });
отказ(И.чейХод(партия), { действие: 'карта', id: '♠Т' });
отказ(партия.игроки.find(к => к !== И.чейХод(партия)), { действие: 'торг', масть: null });
for (const кто of партия.игроки) {
  const вид = И.видДляИгрока(партия, кто).деберц;
  assert.equal(вид.рука.length, 6);
  const текст = JSON.stringify(вид);
  const чужие = партия.игра.руки[1 - партия.игроки.indexOf(кто)];
  for (const к of чужие) assert(!текст.includes('"id":"' + к.id + '"'), 'Чужие карты не передаются');
  assert(!текст.includes('запас') && !текст.includes('сыграно') && !текст.includes('место-а'));
  вид.рука[0].имя = 'сломано';
  assert(!JSON.stringify(партия).includes('сломано'), 'Вид не отдаёт изменяемые ссылки на партию');
}
for (let шаг = 0; !партия.завершена; шаг++) {
  assert(шаг < 5000);
  assert(И.ходЗаБота(партия, И.чейХод(партия), 'сложный'));
  if (партия.игра.последняяВзятка) {
    for (const [i, кто] of партия.игроки.entries()) {
      const вид = И.видДляИгрока(партия, кто).деберц;
      assert.deepEqual(вид.очки, [партия.игра.очки[i], партия.игра.очки[1 - i]]);
      assert.equal(вид.последняяВзятка.карты.length, 2);
      assert.deepEqual(вид.последняяВзятка.карты.map(к => к.карта.id), партия.игра.последняяВзятка.карты.map(к => к.карта.id));
      for (const к of вид.последняяВзятка.карты) assert(к.игрок === 0 || к.игрок === 1);
      вид.последняяВзятка.карты[0].карта.имя = 'сломано';
      assert(!JSON.stringify(партия).includes('сломано'), 'История не даёт изменить исходную партию');
    }
  }
}
assert(партия.результат); assert.equal(партия.проигравшие.length, 1);
отказ(партия.результат, { действие: 'раздача' });

const адрес = 'http://127.0.0.1:' + (process.argv[2] || '8837');
const цель = Number(process.argv[3] || 301);
async function запрос(путь, тело) {
  const ответ = await fetch(адрес + '/' + encodeURIComponent(путь), { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(тело) });
  return { статус: ответ.status, ...await ответ.json() };
}
(async () => {
  const а = await запрос('создать', { игра: 'деберц', имя: 'Первый', цельДеберца: цель });
  assert.equal(а.статус, 200, JSON.stringify(а));
  const б = await запрос('войти', { код: а.код, имя: 'Второй' });
  assert.equal(б.статус, 200);
  const игроки = [а, б].map(к => ({ код: а.код, пропуск: к.пропуск }));
  try {
    const третий = await запрос('войти', { код: а.код, имя: 'Лишний' });
    assert.notEqual(третий.статус, 200);
    let кончилась = false;
    for (let шаг = 0; шаг < 3000; шаг++) {
      const виды = await Promise.all(игроки.map(к => запрос('состояние', к)));
      виды.forEach(в => { assert.equal(в.состояние.игра, 'деберц'); assert.equal(в.состояние.деберц.цель, цель); });
      if (виды[0].состояние.завершена) { кончилась = true; break; }
      const чей = виды.findIndex(в => в.состояние.яХожу);
      assert(чей >= 0);
      const и = виды[чей].состояние.деберц;
      assert.equal(и.очки.length, 2, 'Сервер передаёт очки текущей сдачи');
      if (и.последняяВзятка) assert.equal(и.последняяВзятка.карты.length, 2, 'История взятки доходит по HTTP');
      let действие;
      if (и.фаза === 'торговля') действие = { действие: 'торг', масть: и.круг === 1 ? и.открытая.масть : П.масти.find(м => м !== и.открытая.масть) };
      else if (и.фаза === 'игра') действие = { действие: 'карта', id: и.можно[0] };
      else действие = { действие: и.фаза === 'взятка' ? 'взятка' : 'раздача' };
      const ответ = await запрос('ход', { ...игроки[чей], ...действие });
      assert.equal(ответ.принято, true, JSON.stringify(ответ));
    }
    assert(кончилась, 'Сетевая партия завершилась');
    for (const к of игроки) assert.equal((await запрос('ход', { ...к, действие: 'ещё' })).принято, true);
    const снова = await запрос('состояние', игроки[0]);
    assert.equal(снова.состояние.завершена, false);
    assert.equal(снова.состояние.деберц.цель, цель, 'Реванш сохраняет цель комнаты');
    assert.deepEqual(снова.состояние.деберц.счёт, [0, 0]);
    console.log('Деберц: серверные правила, приватность рук, отказы, HTTP-партия до ' + цель + ' и реванш — OK');
  } finally { await Promise.all(игроки.map(к => запрос('выйти', к))); }
})().catch(e => { console.error(e); process.exitCode = 1; });
