/* =====================================================================
   Поиск тупиков на всех трёх уровнях соперника.

   Тупик — это положение, из которого человек не может сделать НИЧЕГО:
   на экране нет ни карты, которой разрешено сходить, ни нужной кнопки.
   Правила показа кнопок взяты из js/game.js (функция рисоватьПодсказкуИКнопки):

     фаза «атака»        — кнопок нет; значит у ходящего обязана быть
                           хотя бы одна карта, которую разрешено положить;
     фаза «защита»       — у защищающегося всегда есть кнопка «Беру»;
     «подкидывание»/«докидывание» — у атакующего всегда есть «Бито»/«Готово».

   Отдельно проверяем, что партия не может встать намертво: после каждого
   хода что-то обязано меняться, и партия обязана закончиться.

   Запуск: node tests/проверка-тупиков-уровней.js [партий на каждую пару]
   ===================================================================== */

'use strict';

const игра = require(require('path').join(__dirname, '..', 'js', 'game.js'));

const ПАРТИЙ = Number(process.argv[2]) || 800;
const ПРЕДЕЛ_ХОДОВ = 500;

let зерно = 777;
Math.random = function () {
  зерно = (зерно * 1103515245 + 12345) % 2147483648;
  return зерно / 2147483648;
};

/** Ходит наугад — так перебирается больше положений, чем при игре бота. */
function случайныйХод(п, игрок) {
  const фаза = игра.фаза(п);
  const рука = п.руки[игрок];
  if (фаза === 'защита') {
    const варианты = [];
    п.стол.forEach(function (пара, iП) {
      if (пара.защита) return;
      рука.forEach(function (к, iК) { if (игра.бьёт(к, пара.атака, п.козырь)) варианты.push([iП, iК]); });
    });
    if (варианты.length === 0 || Math.random() < 0.3) { игра.объявитьБеру(п); return 'беру'; }
    const в = варианты[Math.floor(Math.random() * варианты.length)];
    игра.отбить(п, в[0], в[1]);
    return 'отбился';
  }
  const годные = [];
  for (let i = 0; i < рука.length; i++) if (игра.можноПоложить(п, рука[i])) годные.push(i);
  if (годные.length === 0 || (фаза !== 'атака' && Math.random() < 0.45)) { игра.завершитьПодход(п); return 'бито'; }
  игра.положитьВАтаку(п, игрок, годные[Math.floor(Math.random() * годные.length)]);
  return 'положил';
}

/** Что игрок реально может сделать на экране в этом положении. */
function естьЧтоНажать(п, игрок) {
  const фаза = игра.фаза(п);
  const рука = п.руки[игрок];
  if (фаза === 'защита') return true;                                  // всегда есть «Беру»
  if (фаза === 'подкидывание' || фаза === 'докидывание') return true;  // всегда есть «Бито»/«Готово»
  // Фаза «атака»: кнопок нет, спасти может только карта.
  for (const к of рука) if (игра.можноПоложить(п, к)) return true;
  return false;
}

const тупики = [];
let положенийАтаки = 0;
let партийВсего = 0;

function прогон(название, ходЧеловека, уровеньБота, смещение) {
  for (let н = 1; н <= ПАРТИЙ && тупики.length < 8; н++) {
    зерно = (н * 8191 + смещение) % 2147483648;
    const п = игра.создатьПартию(уровеньБота);
    партийВсего++;
    let шагов = 0;

    while (!п.завершена && шагов++ < ПРЕДЕЛ_ХОДОВ) {
      const кто = игра.ктоХодит(п);
      if (кто === null) {
        тупики.push(название + ', партия ' + н + ': партия не окончена, а ходить некому');
        break;
      }
      if (игра.фаза(п) === 'атака') положенийАтаки++;
      if (!естьЧтоНажать(п, кто)) {
        тупики.push(название + ', партия ' + н + ': ход «' + кто + '», фаза «' + игра.фаза(п) +
          '», в руке ' + п.руки[кто].length + ' карт, но ни одной положить нельзя и кнопок не будет. ' +
          'В колоде ' + п.колода.length + ', у соперника ' + п.руки[игра.защищается(п)].length);
        break;
      }
      if (кто === 'человек') случайныйХод(п, кто);
      else игра.ходБота(п, кто, уровеньБота);
    }
    if (!п.завершена && шагов >= ПРЕДЕЛ_ХОДОВ) {
      тупики.push(название + ', партия ' + н + ': не закончилась за ' + ПРЕДЕЛ_ХОДОВ + ' ходов');
    }
  }
}

console.log('=== Поиск тупиков на всех уровнях ===');
console.log('партий на каждую пару: ' + ПАРТИЙ + '\n');

прогон('человек наугад против лёгкого', null, 'лёгкий', 11);
прогон('человек наугад против обычного', null, 'обычный', 22);
прогон('человек наугад против сложного', null, 'сложный', 33);

console.log('партий сыграно: ' + партийВсего);
console.log('положений «стол пуст, надо ходить» проверено: ' + положенийАтаки);
if (тупики.length === 0) {
  console.log('=== Итог: тупиков нет. Ходящему всегда есть что нажать ===');
  process.exit(0);
}
console.log('НАЙДЕНЫ ТУПИКИ:');
тупики.forEach(function (т) { console.log('  - ' + т); });
process.exit(1);
