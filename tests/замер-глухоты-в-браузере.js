/* =====================================================================
   Замер окна «глухоты» руки после нажатия кнопки (ГЛУХОТА_ПОСЛЕ_КНОПКИ).

   ЭТО НЕ АВТОПРОГОН ДЛЯ NODE. Файл целиком вставляется в консоль браузера,
   когда игра уже открыта (http://…/index.html) и идёт партия против бота.
   Node его запускать не надо — здесь нужен живой экран с картами.

   Зачем он нужен. Окно глухоты защищает от «хвоста» касания: палец,
   нажавший кнопку, не должен доиграть картой. Но в то же окно попадает
   и осознанный тап — например, когда соперник забрал карты и ход тут же
   вернулся к игроку. Чтобы решать про это число не на глаз, здесь собраны
   замеры.

   САМО ЧИСЛО ЗДЕСЬ НЕ ПОВТОРЯЕТСЯ НАРОЧНО. Оно живёт в js/game.js
   (ГЛУХОТА_ПОСЛЕ_КНОПКИ), и переписывать его сюда нельзя: поменяют там —
   шапка начнёт врать. Замер каждый раз спрашивает у самой игры, на сколько
   миллисекунд поставлена глухота, и печатает это в ответе («глухотаПоставленаНа»).
   Для памяти: сперва окно было 350 мс, по итогам замеров штаб сократил его
   до 150 мс — но проверять надо не по этой строке, а по ответу замера.

     замерГлухоты.хвост()      — может ли повторное нажатие в точку кнопки
                                 вообще долететь до карты (двигается ли
                                 вёрстка, что оказывается под пальцем);
     замерГлухоты.проба(мс)    — ОДИН осознанный тап через столько-то
                                 миллисекунд после кнопки: прошёл, пропал
                                 в глухоте или игра ответила отказом;
     замерГлухоты.пробыПодряд([…]) — несколько таких проб по очереди,
                                 каждая со своим свежим положением на столе;
     замерГлухоты.статистика() — сколько нажатий кнопок оставляют ход
                                 за игроком (то есть сколько из них
                                 попадают в опасный случай) и за сколько
                                 миллисекунд перерисовывается рука.

   Порядок работы: вставить файл, потом звать замеры по одному.
   ===================================================================== */

(function () {
  'use strict';

  const пауза = (мс) => new Promise((r) => setTimeout(r, мс));
  const веер = () => document.getElementById('карты-человека');
  const панель = () => document.getElementById('панель-кнопок');
  const кнопкаКонца = () => document.getElementById('кнопка-завершить');
  const виденИтог = () => document.getElementById('экран-результата').classList.contains('экран--виден');
  const видна = (у) => у && у.offsetParent !== null && у.getBoundingClientRect().height > 0;
  const рамка = (у) => {
    const р = у.getBoundingClientRect();
    return { верх: Math.round(р.top), низ: Math.round(р.bottom), высота: Math.round(р.height) };
  };

  /** Сходить один раз законным ходом — нужно, чтобы дойти до нужного положения. */
  function сходитьЗаконно() {
    if (!партия || партия.завершена || !сейчасМойХод()) return;
    const рука = партия.руки.человек;
    if (фаза(партия) === 'защита') {
      const пара = партия.стол.findIndex((п) => !п.защита);
      const цели = [];
      if (пара >= 0) {
        рука.forEach((к, i) => { if (бьёт(к, партия.стол[пара].атака, партия.козырь)) цели.push(i); });
      }
      if (цели.length) veer_click(цели[0]);
      else document.getElementById('кнопка-беру').click();
      return;
    }
    const годные = [];
    рука.forEach((к, i) => { if (картаСейчасХодит(к) === true) годные.push(i); });
    if (годные.length) veer_click(годные[0]);
    else if (видна(кнопкаКонца())) кнопкаКонца().click();
  }
  function veer_click(индекс) {
    const узел = веер().children[индекс];
    if (узел) узел.click();
  }

  /** Доиграть до положения, где видна кнопка конца подхода. */
  async function дойтиДоКнопки(нужноБерёт) {
    for (let шаг = 0; шаг < 900; шаг++) {
      if (виденИтог()) { document.getElementById('кнопка-ещё').click(); await пауза(500); continue; }
      const готово = партия && !партия.завершена && сейчасМойХод() && видна(кнопкаКонца()) &&
        (!нужноБерёт || партия.берёт);
      if (готово) return true;
      сходитьЗаконно();
      await пауза(70);
    }
    return false;
  }

  const замерГлухоты = {};

  /**
   * Может ли «хвост» касания долететь до карты. Смотрим, что оказывается
   * под той же точкой экрана после того, как кнопка спряталась, и считаем
   * нажатия, которые всё-таки дошли до руки.
   */
  замерГлухоты.хвост = async function () {
    if (!(await дойтиДоКнопки(false))) return 'не удалось дойти до кнопки конца подхода';
    const пойманные = [];
    const счётчик = (е) => пойманные.push(String(е.target.className || е.target.id).slice(0, 24));
    веер().addEventListener('click', счётчик, true);

    const к = кнопкаКонца().getBoundingClientRect();
    const x = к.x + к.width / 2;
    const y = к.y + к.height / 2;
    const рукаДо = рамка(веер());
    const панельДо = рамка(панель());

    кнопкаКонца().click();
    await пауза(1);
    const сразу = document.elementFromPoint(x, y);
    if (сразу) сразу.dispatchEvent(new MouseEvent('click', { bubbles: true, cancelable: true, clientX: x, clientY: y }));
    await пауза(150);
    const позже = document.elementFromPoint(x, y);
    if (позже) позже.dispatchEvent(new MouseEvent('click', { bubbles: true, cancelable: true, clientX: x, clientY: y }));
    await пауза(250);
    веер().removeEventListener('click', счётчик, true);

    return {
      точкаКнопки: { x: Math.round(x), y: Math.round(y) },
      подТочкойСразу: сразу ? (сразу.id || сразу.className) : 'ничего',
      подТочкойЧерез150мс: позже ? (позже.id || позже.className) : 'ничего',
      рукаСдвинулась: рукаДо.верх !== рамка(веер()).верх,
      панельСдвинулась: панельДо.верх !== рамка(панель()).верх,
      зазорМеждуРукойИКнопкой: Math.round(к.top - рукаДо.низ) + ' px',
      хвостовыхНажатийДолетелоДоКарт: пойманные.length
    };
  };

  /**
   * ОДИН осознанный тап через заданное время после кнопки. Берём самый
   * опасный случай: соперник забрал карты («Готово»), и ход тут же вернулся
   * к нам, то есть тап законен с первой же миллисекунды.
   *
   * Важно различать два разных «не сработало»:
   *   — ГЛУХО: игра не ответила вовсе (ни слова, ни вспышки, ни звука) —
   *     это и есть окно глухоты;
   *   — ОТКАЗ: игра ответила, но ход был не по правилам (например, первый
   *     тап уже сходил картой, и второй такой же уже нельзя).
   * Раньше проба считала только «легла ли карта на стол» и путала одно
   * с другим: после удачного тапа второй в том же подходе объявлялся
   * «пропавшим», хотя игра честно ответила отказом.
   */
  замерГлухоты.проба = async function (черезМс) {
    const задержка = черезМс === undefined ? 200 : черезМс;
    if (!(await дойтиДоКнопки(true))) return 'соперник так и не сказал «Беру» — повторите замер';

    const t0 = performance.now();
    const перерисовка = { когда: null };
    const н = new MutationObserver(() => {
      if (перерисовка.когда === null) перерисовка.когда = Math.round(performance.now() - t0);
    });
    н.observe(веер(), { childList: true });

    кнопкаКонца().click();
    const глухотаМс = Math.round(рукаГлухаДо - Date.now());
    const ходОсталсяМой = сейчасМойХод();

    await пауза(задержка);

    /* Бывает, что этим самым нажатием партия и кончилась: карт не осталось,
       открылся экран итога. Тогда рука не отвечает совсем — но не из-за
       глухоты, а потому, что играть уже нечем. Такую пробу в счёт не берём:
       иначе она притворится «глухотой» и испортит замер. */
    if (!партия || партия.завершена || виденИтог()) {
      н.disconnect();
      return { тапЧерез: задержка + ' мс', итог: 'проба не в счёт: этим нажатием кончилась партия' };
    }

    // Что было на экране до тапа — чтобы поймать любой ответ игры
    const подсказка = document.getElementById('подсказка');
    const текстДо = подсказка.textContent;
    const столДо = партия.стол.length;
    let ответилаСловами = false;
    let вздрогнулаКарта = false;
    const н2 = new MutationObserver(() => { ответилаСловами = ответилаСловами || подсказка.textContent !== текстДо; });
    н2.observe(подсказка, { childList: true, characterData: true, subtree: true });
    const н3 = new MutationObserver((мут) => мут.forEach((м) => {
      if (м.target.classList && м.target.classList.contains('карта--отказ')) вздрогнулаКарта = true;
    }));
    н3.observe(веер(), { attributes: true, subtree: true, attributeFilter: ['class'] });

    veer_click(0);
    await пауза(80);
    н2.disconnect(); н3.disconnect(); н.disconnect();

    const картаЛегла = партия.стол.length > столДо;
    const играОтветила = картаЛегла || ответилаСловами || вздрогнулаКарта;

    return {
      глухотаПоставленаНа: глухотаМс + ' мс',
      рукаПерерисованаЧерез: перерисовка.когда + ' мс',
      ходОсталсяМой: ходОсталсяМой,
      тапЧерез: задержка + ' мс',
      итог: !играОтветила ? 'ГЛУХО — игра не ответила вовсе'
        : (картаЛегла ? 'ПРОШЁЛ — карта легла на стол' : 'игра ответила отказом (ход был не по правилам)'),
      подробно: { картаЛегла: картаЛегла, ответилаСловами: ответилаСловами, вздрогнулаКарта: вздрогнулаКарта }
    };
  };

  /**
   * Несколько проб подряд, каждая — со своим свежим положением на столе.
   * Так значения не мешают друг другу: после удачного тапа стол уже другой.
   */
  замерГлухоты.пробыПодряд = async function (список) {
    const времена = Array.isArray(список) ? список : [50, 100, 150, 200, 300];
    const итоги = [];
    for (const когда of времена) {
      const один = await замерГлухоты.проба(когда);
      итоги.push(typeof один === 'string' ? { тапЧерез: когда + ' мс', итог: один } : один);
      await пауза(400);
    }
    return итоги;
  };

  /**
   * Сколько нажатий кнопок конца подхода оставляют ход за игроком —
   * то есть сколько из них попадают в опасный случай. Ставится один раз,
   * дальше просто играйте; итог спрашивать через замерГлухоты.итогСтатистики().
   */
  замерГлухоты.статистика = function () {
    if (window.__замерКнопок) return 'уже слежу; спросите замерГлухоты.итогСтатистики()';
    window.__замерКнопок = { случаи: [] };
    ['кнопка-завершить', 'кнопка-беру'].forEach(function (id) {
      const кнопка = document.getElementById(id);
      if (!кнопка) return;
      кнопка.addEventListener('click', function () {
        const t0 = performance.now();
        const случай = {
          кнопка: id + ' («' + кнопка.textContent + '»)',
          рукаДо: рамка(веер()), панельДо: рамка(панель()),
          перерисовкаМс: null, ходОсталсяМой: null, рукаПосле: null, панельПосле: null
        };
        const н = new MutationObserver(function () {
          if (случай.перерисовкаМс === null) случай.перерисовкаМс = Math.round(performance.now() - t0);
        });
        н.observe(веер(), { childList: true });
        setTimeout(function () {
          случай.ходОсталсяМой = сейчасМойХод();
          случай.рукаПосле = рамка(веер());
          случай.панельПосле = рамка(панель());
          н.disconnect();
          window.__замерКнопок.случаи.push(случай);
        }, 60);
      }, true);
    });
    return 'слежу за кнопками конца подхода — играйте, потом спросите итог';
  };

  замерГлухоты.итогСтатистики = function () {
    const с = (window.__замерКнопок || { случаи: [] }).случаи;
    if (!с.length) return 'нажатий пока не было';
    const перерисовки = с.map((х) => х.перерисовкаМс).filter((х) => х !== null);
    const опасные = с.filter((х) => х.ходОсталсяМой);
    const сдвиги = с.filter((х) => х.рукаПосле && (х.рукаПосле.верх !== х.рукаДо.верх ||
      х.панельПосле.верх !== х.панельДо.верх));
    const поКнопкам = {};
    с.forEach(function (х) {
      поКнопкам[х.кнопка] = поКнопкам[х.кнопка] || { всего: 0, ходОсталсяМой: 0 };
      поКнопкам[х.кнопка].всего++;
      if (х.ходОсталсяМой) поКнопкам[х.кнопка].ходОсталсяМой++;
    });
    return {
      нажатий: с.length,
      ходОсталсяМой: опасные.length,
      доляОпасных: Math.round(100 * опасные.length / с.length) + '%',
      поКнопкам: поКнопкам,
      перерисовкаРукиМс: {
        мин: Math.min.apply(null, перерисовки),
        макс: Math.max.apply(null, перерисовки),
        среднее: Math.round(перерисовки.reduce((а, б) => а + б, 0) / перерисовки.length)
      },
      сдвиговВёрстки: сдвиги.length
    };
  };

  window.замерГлухоты = замерГлухоты;
  console.log('Замер готов. Зовите: замерГлухоты.хвост(), замерГлухоты.проба(200), ' +
    'замерГлухоты.пробыПодряд([50, 100, 150, 200, 300]), ' +
    'замерГлухоты.статистика() и потом замерГлухоты.итогСтатистики().');
})();
