/** Вычисленный вид заголовка, подписей разделов и кнопок контроля
 *  времени на шаге бота — то, что реально видит игрок, а не имена
 *  классов в разметке. */
async function замерШага(страница, селекторыКонтроля) {
  return страница.evaluate((селекторыКонтроля) => {
    function видУзла(узел) {
      if (!узел) return null;
      const в = getComputedStyle(узел);
      const прямоугольник = узел.getBoundingClientRect();
      return {
        текст: узел.textContent.trim(),
        textAlign: в.textAlign,
        цвет: в.color,
        размерШрифта: в.fontSize,
        фон: в.backgroundColor,
        рамкаШирина: в.borderTopWidth,
        рамкаСтиль: в.borderTopStyle,
        рамкаЦвет: в.borderTopColor,
        видим: узел.offsetParent !== null,
        // Центр по горизонтали в пикселях экрана — так проверяем
        // ФАКТИЧЕСКОЕ положение подписи, а не одно только CSS-свойство
        // text-align: подпись может стоять по центру и через выравнивание
        // текста, и через центрирование самого блока во flex-контейнере
        // (у подписей разделов работает именно второй способ — их
        // центрирует общий класс «.выбор» с align-items:center).
        центрX: прямоугольник.left + прямоугольник.width / 2
      };
    }

    const заголовок = document.querySelector('.экран--виден .заголовок') ||
      document.querySelector('.экран--виден h2.заголовок');
    const подписи = Array.from(document.querySelectorAll('.экран--виден .выбор__подпись'));
    const кнопкиКонтроля = селекторыКонтроля.map((ид) => видУзла(document.getElementById(ид)));

    return {
      заголовок: видУзла(заголовок),
      подписи: подписи.map(видУзла),
      кнопкиКонтроля: кнопкиКонтроля
    };
  }, селекторыКонтроля);
}

function описатьВид(в) {
  if (!в) return 'узел не найден';
  return 'текст="' + в.текст + '" align=' + в.textAlign + ' цвет=' + в.цвет +
    ' размер=' + в.размерШрифта + ' фон=' + в.фон + ' рамка=' + в.рамкаШирина + ' ' + в.рамкаСтиль;
}

/** Плашка — это когда у варианта есть и заметная рамка, и не совсем
 *  прозрачный фон ИЛИ хотя бы одно из двух (рамка ИЛИ заливка активного
 *  варианта). «Голый текст» — ни рамки, ни фона вовсе. */
function похожеНаПлашку(в) {
  if (!в) return false;
  const естьРамка = в.рамкаСтиль !== 'none' && в.рамкаШирина !== '0px';
  const естьФон = в.фон !== 'rgba(0, 0, 0, 0)' && в.фон !== 'transparent';
  return естьРамка || естьФон;
}

