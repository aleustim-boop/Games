function испортитьКопиюШахмат(оригинал) {
  const замены = [
    // Заголовок — прежний текст, выровнен влево явным style (тем же
    // приёмом, каким сама плашка стала бы «не такой» и без правки CSS).
    ['<h2 class="заголовок">Игра с ботом</h2>',
      '<h2 class="заголовок" style="text-align:left">Играть с ботом</h2>'],
    // Раздел «Сложность бота» — назад на крупный белый h2 слева.
    ['<span class="выбор__подпись">Сложность бота</span>',
      '</div><h2 class="путь__раздел">Сложность бота</h2><div class="выбор" style="display:contents">'],
    // Раздел «Контроль времени» — то же самое.
    ['<span class="выбор__подпись">Контроль времени</span>',
      '</div><h2 class="путь__раздел">Контроль времени</h2><div class="выбор" style="display:contents">'],
    // Контроль времени — назад на «.переключатель__вариант»: плашку
    // (фон и box-shadow) получает только выбранный «Без часов», три
    // остальных варианта остаются голым текстом без рамки и фона.
    ['class="кнопка кнопка--выбор кнопка--активная" role="radio" aria-checked="true" data-контроль="нет"',
      'class="переключатель__вариант переключатель__вариант--выбран" role="radio" aria-checked="true" data-контроль="нет"'],
    ['class="кнопка кнопка--выбор" role="radio" aria-checked="false" data-контроль="блиц"',
      'class="переключатель__вариант" role="radio" aria-checked="false" data-контроль="блиц"'],
    ['class="кнопка кнопка--выбор" role="radio" aria-checked="false" data-контроль="рапид"',
      'class="переключатель__вариант" role="radio" aria-checked="false" data-контроль="рапид"'],
    ['class="кнопка кнопка--выбор" role="radio" aria-checked="false" data-контроль="классика"',
      'class="переключатель__вариант" role="radio" aria-checked="false" data-контроль="классика"'],
    // Нижняя кнопка «Назад» — убираем совсем, как было до правки.
    ['<button id="лобби-бот-назад" type="button" class="кнопка кнопка--мелкая">Назад</button>', '']
  ];

  let испорченный = оригинал;
  for (const [искать, менять] of замены) {
    if (испорченный.indexOf(искать) === -1) {
      throw new Error('в шахматы.html не нашёлся кусок «' + искать + '» — разметка поменялась, обновите эту проверку');
    }
    испорченный = испорченный.replace(искать, менять);
  }

  const путьКопии = path.join(os.tmpdir(), 'games-шахматы-шаг-бота-испорченный-' + Date.now() + '.html');
  fs.writeFileSync(путьКопии, испорченный, 'utf8');
  const текстСДиска = fs.readFileSync(путьКопии, 'utf8');
  return { путьКопии, текстСДиска, отличается: текстСДиска !== оригинал };
}

