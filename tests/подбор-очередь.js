'use strict';

/* =====================================================================
   ПОДБОР СОПЕРНИКА: очередь ожидания (server/подбор.js), Э1.

   Что проверяем. Чистый node, никакого HTTP и никакого сервера комнат —
   функции модуля дёргаются напрямую. Шесть сценариев из плана:
     1) двое с одинаковыми правилами сводятся сразу;
     2) с подкрученным (коротким) порогом статус говорит «пора_бота»;
     3) подкидной и переводной (разные полки) друг с другом не сводятся;
     4) отмена убирает из очереди — статус после неё «не_найдено»;
     5) чужим ключОжидания чужой результат не прочитать (ключ — длинная
        случайная строка, подделать на практике нельзя);
     6) двойное «встать» одним номером Telegram на одну полку не даёт
        второй записи — возвращается та же самая.

   Запуск:
       node tests/подбор-очередь.js

   Ломающий прогон (проверка обязана покраснеть):
       node tests/подбор-очередь.js --сломать
   «--сломать» подменяет наблюдаемое прямо в проверке (не в модуле):
   результат сведения подменяется на «чужого» соперника, статус после
   отмены — на «ещё ждёт», а запись при двойном «встать» — на новую со
   своим ключом. Все шесть сценариев обязаны провалиться.

   Выход 0 — провалов нет, 1 — есть.
   ===================================================================== */

const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const подбор = require(path.join(КОРЕНЬ, 'server', 'подбор.js'));

const ЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;
if (ЛОМАТЬ) {
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: наблюдаемые результаты подменяются в самой ' +
              'проверке, модуль не трогая; проверка обязана покраснеть ***');
}

let проверок = 0;
const провалы = [];

function проверить(условие, что) {
  проверок++;
  if (!условие) {
    провалы.push(что);
    console.log('  ПРОВАЛ: ' + что);
  }
}

function подождать(мс) {
  return new Promise(function (готово) { setTimeout(готово, мс); });
}

/* Игроки. Номера выдуманы, но выглядят как настоящие номера Telegram. */
const АНЯ = 301, БОРЯ = 302, ВИТЯ = 303, ГАЛЯ = 304, ДИМА = 305, ЕГОР = 306;

/* Правила стола по умолчанию для большинства сценариев: дурак 1×1,
   переводной. Число мест и переводной/подкидной — единственные правила,
   от которых зависит полка.

   Каждый сценарий берёт СВОЁ значение местВСтоле — чисто как номер
   дорожки для проверки (в жизни сейчас только 1×1), чтобы записи одного
   сценария физически не могли попасться партнёром другому сценарию,
   если тот случайно забыл кого-то отменить. */
function правила(местВСтоле, переводной) {
  return { игра: 'дурак', местВСтоле: местВСтоле, переводной: переводной };
}

async function проверкаСведения() {
  console.log('1) двое с одинаковыми правилами сводятся сразу');

  const первый = подбор.встатьВОчередь(Object.assign(
    { номерТелеграм: АНЯ, имя: 'Аня', метка: 'вкладка-1' }, правила(11, true)));
  проверить(первый.статус === 'ждёт', 'первый вставший должен ждать, а не сводиться сам с собой');

  let второй = подбор.встатьВОчередь(Object.assign(
    { номерТелеграм: БОРЯ, имя: 'Боря', метка: 'вкладка-2' }, правила(11, true)));

  if (ЛОМАТЬ) {
    /* Порча: подменяем «с кем свели» на несуществующего игрока — доказывает,
       что проверка действительно смотрит в сКем, а не просто в статус. */
    второй = Object.assign({}, второй, { сКем: { номерТелеграм: 999999, имя: 'Чужой' } });
  }

  проверить(второй.статус === 'свели', 'второй вставший должен сразу свестись с первым');
  проверить(второй.сКем && второй.сКем.номерТелеграм === АНЯ,
    'второму должны назвать первого игрока как партнёра');

  const статусПервого = подбор.статус(первый.ключОжидания);
  проверить(статусПервого.статус === 'свели', 'первый при следующем опросе тоже должен узнать о сведении');
  проверить(статусПервого.сКем && статусПервого.сКем.номерТелеграм === БОРЯ,
    'первому должны назвать второго игрока как партнёра');
}

async function проверкаПорогаБота() {
  console.log('2) подкрученный порог — статус «пора подсаживать бота»');

  подбор.подменитьПорогОжиданияДляПроверки(60); // 60 мс вместо 20 секунд, только для этого сценария

  const одиночка = подбор.встатьВОчередь(Object.assign(
    { номерТелеграм: ВИТЯ, имя: 'Витя', метка: 'вкладка-3' }, правила(22, true)));
  проверить(одиночка.статус === 'ждёт', 'в одиночку на пустой полке — только ждать');

  await подождать(120);

  let статусПослеОжидания = подбор.статус(одиночка.ключОжидания);
  if (ЛОМАТЬ) {
    /* Порча: делаем вид, что время ещё не вышло. */
    статусПослеОжидания = { статус: 'ждёт' };
  }
  проверить(статусПослеОжидания.статус === 'пора_бота',
    'после истечения короткого порога статус обязан быть «пора_бота»');

  подбор.подменитьПорогОжиданияДляПроверки(null); // возвращаем обычные 20 секунд для остальных сценариев

  /* Модуль сам не убирает запись при переходе «пора_бота» — это решает
     вызывающий код (Э2/Э3), которого здесь нет. Убираем руками, чтобы
     одиночка не остался висеть на полке «переводной» и не сбил
     следующий сценарий про разные правила. */
  подбор.отменить(одиночка.ключОжидания);
}

async function проверкаРазныхПолок() {
  console.log('3) подкидной и переводной не сводятся друг с другом');

  const переводной = подбор.встатьВОчередь(Object.assign(
    { номерТелеграм: ГАЛЯ, имя: 'Галя', метка: 'вкладка-4' }, правила(33, true)));
  let подкидной = подбор.встатьВОчередь(Object.assign(
    { номерТелеграм: ДИМА, имя: 'Дима', метка: 'вкладка-5' }, правила(33, false)));

  if (ЛОМАТЬ) {
    /* Порча: делаем вид, что подкидного тоже свели — с переводным игроком. */
    подкидной = { статус: 'свели', сКем: { номерТелеграм: ГАЛЯ } };
  }

  проверить(переводной.статус === 'ждёт', 'переводной игрок ждёт на своей полке один');
  проверить(подкидной.статус === 'ждёт', 'подкидной игрок ждёт на своей полке один, разные правила не сводятся');

  const статусПереводного = подбор.статус(переводной.ключОжидания);
  проверить(статусПереводного.статус === 'ждёт', 'переводной так и остаётся ждать, партнёра с его правилами нет');
}

async function проверкаОтмены() {
  console.log('4) отмена убирает из очереди');

  const запись = подбор.встатьВОчередь(Object.assign(
    { номерТелеграм: ЕГОР, имя: 'Егор', метка: 'вкладка-6' }, правила(44, true)));
  проверить(запись.статус === 'ждёт', 'встал и ждёт, партнёра пока нет');

  const ответ = подбор.отменить(запись.ключОжидания);
  проверить(ответ.ок === true, 'отмена существующей записи должна пройти успешно');

  let статусПослеОтмены = подбор.статус(запись.ключОжидания);
  if (ЛОМАТЬ) {
    /* Порча: делаем вид, что запись всё ещё жива после отмены. */
    статусПослеОтмены = { статус: 'ждёт' };
  }
  проверить(статусПослеОтмены.статус === 'не_найдено',
    'после отмены статус по этому ключу обязан быть «не_найдено»');

  const повторнаяОтмена = подбор.отменить(запись.ключОжидания);
  проверить(повторнаяОтмена.ок === false, 'повторная отмена уже отменённого ключа не должна притворяться успехом');
}

async function проверкаЧужогоКлюча() {
  console.log('5) чужим ключОжидания чужой результат не забрать');

  const свой = подбор.встатьВОчередь(
    { номерТелеграм: 555001, имя: 'Пятый-первый', метка: 'a', игра: 'дурак', местВСтоле: 55, переводной: true });
  подбор.встатьВОчередь(
    { номерТелеграм: 555002, имя: 'Пятый-второй', метка: 'b', игра: 'дурак', местВСтоле: 55, переводной: true });

  let чужойКлюч = 'явно-выдуманный-ключ-которого-не-существует-в-очереди';
  if (ЛОМАТЬ) {
    /* Порча: подсовываем настоящий ключ своей же записи — тогда «чужой»
       запрос ожидаемо совпадёт, и проверка обязана провалиться. */
    чужойКлюч = свой.ключОжидания;
  }

  const ответПоЧужому = подбор.статус(чужойКлюч);
  проверить(ответПоЧужому.статус === 'не_найдено', 'выдуманным/чужим ключом статус читать нельзя');

  const отменаПоЧужому = подбор.отменить(чужойКлюч);
  проверить(отменаПоЧужому.ок === false, 'выдуманным/чужим ключом отменить чужую запись нельзя');

  проверить(typeof свой.ключОжидания === 'string' && свой.ключОжидания.length >= 32,
    'ключОжидания должен быть длинной случайной строкой, а не коротким/предсказуемым значением');
}

async function проверкаДвойногоВстатия() {
  console.log('6) двойное «встать» одним номером не даёт второй записи');

  const первый = подбор.встатьВОчередь(
    { номерТелеграм: 606001, имя: 'Шестой', метка: 'первая-вкладка', игра: 'дурак', местВСтоле: 66, переводной: false });
  let второй = подбор.встатьВОчередь(
    { номерТелеграм: 606001, имя: 'Шестой', метка: 'вторая-вкладка-того-же-номера', игра: 'дурак', местВСтоле: 66, переводной: false });

  if (ЛОМАТЬ) {
    /* Порча: делаем вид, что второе «встать» завело новый ключ. */
    второй = Object.assign({}, второй, { ключОжидания: второй.ключОжидания + '-подделка' });
  }

  проверить(первый.ключОжидания === второй.ключОжидания,
    'повторное «встать» тем же номером Telegram на ту же полку обязано вернуть ту же запись');
}

async function основной() {
  await проверкаСведения();
  await проверкаПорогаБота();
  await проверкаРазныхПолок();
  await проверкаОтмены();
  await проверкаЧужогоКлюча();
  await проверкаДвойногоВстатия();

  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалы.length);
  process.exit(провалы.length ? 1 : 0);
}

основной().catch(function (ошибка) {
  console.error('Проверка упала с ошибкой:', ошибка);
  process.exit(1);
});
