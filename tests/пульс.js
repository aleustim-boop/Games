const СЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;
const КОРЕНЬ = path.join(__dirname, '..');
const ИСХОДНИК = path.join(КОРЕНЬ, 'js', 'пульс.js');

/* --- Мелкая обвязка проверок, как в других проверках проекта. --- */
function новыйПрогон() {
  const провалы = [];
  let проверок = 0;
  const провалыПоСценариям = {};
  let текущийСценарий = '';

  function сценарий(имя) { текущийСценарий = имя; }
  function проверить(условие, что) {
    проверок++;
    if (!условие) {
      провалы.push('[' + текущийСценарий + '] ' + что);
      провалыПоСценариям[текущийСценарий] = (провалыПоСценариям[текущийСценарий] || 0) + 1;
      console.log('  ✗ [' + текущийСценарий + '] ' + что);
    } else {
      console.log('  ✓ [' + текущийСценарий + '] ' + что);
    }
  }
  return { сценарий, проверить, провалы, провалыПоСценариям, счёт: () => проверок };
}

/**
 * Поднять js/пульс.js в песочнице.
 * настройки: { видима, initData, поиск, fetch: 'ок'|'отказ'|'бросить', dataIgra }
 * initData не задан — используется непустая подпись по умолчанию;
 * initData: '' — подписи нет вовсе.
 * dataIgra — значение data-igra тега <script>, которым «подключён» файл;
 * не задан — тега как будто нет вовсе (страница подключила без атрибута).
 */
function поднятьПульс(исходник, настройки) {
  const н = настройки || {};
  const запросы = [];
  const слушателиВидимости = [];
  const активныеИнтервалы = new Map();
  let счётчикИнтервалов = 0;

  /* document.currentScript в настоящем браузере годится ТОЛЬКО пока свой
     тег выполняется синхронно (это верно и при defer) — сразу после
     этого браузер сам стирает его в null. Подделываем ровно то же самое
     геттером: пока vm.runInContext ниже не вернул управление, тег виден;
     дочитает пульс.js его позже (из setTimeout, из обработчика события) —
     увидит уже null, и самозапуск молча не сработает. Так тест и ловит
     ошибку «прочитали currentScript не в том месте». */
  let выполнениеСкриптаЗавершено = false;
  const тегСкрипта = н.dataIgra !== undefined ? { dataset: { igra: н.dataIgra } } : null;

  const документ = {
    visibilityState: н.видима === false ? 'hidden' : 'visible',
    addEventListener: function (имя, дело) {
      if (имя === 'visibilitychange') слушателиВидимости.push(дело);
    },
    removeEventListener: function () {}
  };
  Object.defineProperty(документ, 'currentScript', {
    get: function () { return выполнениеСкриптаЗавершено ? null : тегСкрипта; }
  });

  const телеграм = н.initData === ''
    ? undefined                                  // играем не в Telegram — подписи вовсе нет
    : { WebApp: { initData: н.initData === undefined ? 'подпись-теста' : н.initData } };

  const окно = {
    location: { search: н.поиск !== undefined ? н.поиск : '?сервер=http://тест-сервер.local' },
    Telegram: телеграм,
    Сеть: н.сеть
  };

  const поведениеFetch = н.fetch || 'ок';
  const fetchФункция = function (адрес, настройкиЗапроса) {
    запросы.push({ адрес: адрес, настройки: настройкиЗапроса });
    if (поведениеFetch === 'бросить') throw new Error('сеть недоступна (синхронно)');
    if (поведениеFetch === 'отказ') return Promise.reject(new Error('сеть недоступна'));
    return Promise.resolve({ ok: true });
  };

  const песочница = {
    window: окно,
    document: документ,
    fetch: fetchФункция,
    URLSearchParams: URLSearchParams,
    JSON: JSON, String: String, Promise: Promise,
    console: { log: function () {}, warn: function () {}, error: function () {} },
    setInterval: function (дело, мс) {
      счётчикИнтервалов++;
      активныеИнтервалы.set(счётчикИнтервалов, дело);
      return счётчикИнтервалов;
    },
    clearInterval: function (id) { активныеИнтервалы.delete(id); }
  };
  песочница.globalThis = песочница;
  vm.createContext(песочница);
  vm.runInContext(исходник, песочница, { filename: 'js/пульс.js' });
  выполнениеСкриптаЗавершено = true;   // как в браузере: тег дальше не виден

  return {
    Пульс: окно.Пульс,
    запросы: запросы,
    /** Запустить все сейчас идущие интервалы один раз — как один «тик» в 60 с. */
    тикнуть: function () { for (const дело of Array.from(активныеИнтервалы.values())) дело(); },
    таймеровАктивно: function () { return активныеИнтервалы.size; },
    показать: function () { документ.visibilityState = 'visible'; for (const л of слушателиВидимости.slice()) л(); },
    скрыть: function () { документ.visibilityState = 'hidden'; for (const л of слушателиВидимости.slice()) л(); }
  };
}

function прогон(исходник, прогон) {
  const { сценарий, проверить } = прогон;

  сценарий('А. видима 3 минуты → 4 запроса');
  {
    const п = поднятьПульс(исходник, { видима: true });
    п.Пульс.запустить('дурак');
    проверить(п.запросы.length === 1, 'сразу при запуске — 1 запрос (0 с)');
    п.тикнуть();
    проверить(п.запросы.length === 2, 'через 60 с — 2 запроса');
    п.тикнуть();
    проверить(п.запросы.length === 3, 'через 120 с — 3 запроса');
    п.тикнуть();
    проверить(п.запросы.length === 4, 'через 180 с — 4 запроса (было: ' + п.запросы.length + ')');
  }

  сценарий('Б. скрыта с самого начала → 0');
  {
    const п = поднятьПульс(исходник, { видима: false });
    п.Пульс.запустить('шашки');
    проверить(п.запросы.length === 0, 'на скрытой вкладке пульса нет вовсе');
    проверить(п.таймеровАктивно() === 0, 'на скрытой вкладке таймер не заводится');
    п.тикнуть();
    проверить(п.запросы.length === 0, 'тикать нечему — интервалов не было, запросов по-прежнему нет');
  }

  сценарий('В. без initData → 0');
  {
    const п = поднятьПульс(исходник, { видима: true, initData: '' });
    п.Пульс.запустить('нарды');
    проверить(п.запросы.length === 0, 'без подписи Telegram пульса нет сразу');
    п.тикнуть(); п.тикнуть(); п.тикнуть();
    проверить(п.запросы.length === 0, 'без подписи Telegram пульса нет и после трёх тиков (было: ' + п.запросы.length + ')');
  }

  сценарий('Г. видима → скрыта → видна: таймер и правда останавливается');
  {
    const п = поднятьПульс(исходник, { видима: true });
    п.Пульс.запустить('шахматы');
    проверить(п.запросы.length === 1, 'запрос сразу при запуске');
    п.тикнуть();
    проверить(п.запросы.length === 2, 'через 60 с ещё один запрос');
    п.скрыть();
    проверить(п.таймеровАктивно() === 0, 'вкладку скрыли — таймер снят');
    п.тикнуть(); п.тикнуть(); п.тикнуть();
    проверить(п.запросы.length === 2, 'три «минуты» вслепую на скрытой вкладке не добавили запросов (было: ' + п.запросы.length + ')');
    п.показать();
    проверить(п.запросы.length === 3, 'вкладка снова видна — запрос ушёл сразу, без ожидания минуты');
  }

  сценарий('Д. скрыта, потом видна → запрос сразу');
  {
    const п = поднятьПульс(исходник, { видима: false });
    п.Пульс.запустить('дурак');
    проверить(п.запросы.length === 0, 'пока скрыта — тишина');
    п.показать();
    проверить(п.запросы.length === 1, 'как только вкладка стала видна — пульс сразу');
    проверить(п.таймеровАктивно() === 1, 'и таймер на будущее снова идёт');
  }

  сценарий('Е. тело запроса содержит initData и игру');
  {
    const п = поднятьПульс(исходник, { видима: true, initData: 'подпись-Пети' });
    п.Пульс.запустить('шашки');
    проверить(п.запросы.length === 1, 'один запрос отправлен');
    const запрос = п.запросы[0] || {};
    проверить(String(запрос.адрес || '').indexOf('/пульс') !== -1, 'запрос идёт на путь /пульс (было: ' + запрос.адрес + ')');
    const тело = запрос.настройки && запрос.настройки.body ? JSON.parse(запрос.настройки.body) : {};
    проверить(тело.initData === 'подпись-Пети', 'в теле есть initData (было: ' + JSON.stringify(тело.initData) + ')');
    проверить(тело.игра === 'шашки', 'в теле есть игра (было: ' + JSON.stringify(тело.игра) + ')');
  }

  сценарий('Ё. самозапуск по data-igra (currentScript читается синхронно, как при defer)');
  {
    const п = поднятьПульс(исходник, { видима: true, dataIgra: 'шахматы' });
    проверить(п.запросы.length === 1, 'самозапуск отправил пульс сразу, без единого ручного вызова (было: ' + п.запросы.length + ')');
    проверить(п.таймеровАктивно() === 1, 'и завёл таймер на будущее');
    const тело = п.запросы[0] && п.запросы[0].настройки ? JSON.parse(п.запросы[0].настройки.body) : {};
    проверить(тело.игра === 'шахматы', 'в теле — игра из data-igra (было: ' + JSON.stringify(тело.игра) + ')');
  }

  сценарий('Ж1. самозапуск с незнакомой игрой → 0 запросов');
  {
    const п = поднятьПульс(исходник, { видима: true, dataIgra: 'покер' });
    проверить(п.запросы.length === 0, 'незнакомая игра в data-igra — самозапуска нет вовсе');
    проверить(п.таймеровАктивно() === 0, 'и таймер не заведён');
  }

  сценарий('Ж2. двойной запуск (самозапуск + ручной вызов) → один таймер');
  {
    const п = поднятьПульс(исходник, { видима: true, dataIgra: 'дурак' });
    проверить(п.запросы.length === 1, 'самозапуск уже отправил один пульс');
    п.Пульс.запустить('шашки');   // повторный вызов — должен быть проигнорирован целиком
    проверить(п.запросы.length === 1, 'повторный ручной вызов не шлёт ещё один пульс сразу');
    проверить(п.таймеровАктивно() === 1, 'повторный ручной вызов не заводит второй таймер');
    п.тикнуть();
    проверить(п.запросы.length === 2, 'следующий тик — как обычно, один запрос (не два от двух таймеров)');
    const тело = JSON.parse(п.запросы[1].настройки.body);
    проверить(тело.игра === 'дурак',
      'игра осталась той, с которой запустились в первый раз, повторный вызов её не переписал (было: ' + JSON.stringify(тело.игра) + ')');
  }

  сценарий('Ж. ошибка fetch не бросает исключение');
  {
    let упалоСинхронно = false;
    try {
      const п = поднятьПульс(исходник, { видима: true, fetch: 'бросить' });
      п.Пульс.запустить('дурак');
    } catch (сбой) {
      упалоСинхронно = true;
    }
    проверить(упалоСинхронно === false, 'fetch, бросающий исключение синхронно, не роняет запустить()');

    let упалоНаОтказе = false;
    try {
      const п2 = поднятьПульс(исходник, { видима: true, fetch: 'отказ' });
      п2.Пульс.запустить('нарды');
    } catch (сбой) {
      упалоНаОтказе = true;
    }
    проверить(упалоНаОтказе === false, 'отклонённый промис fetch тоже не роняет запустить()');
  }
}

/**
 * Была ли необработанным отказом та проверка, что не поймала ни одного
 * unhandledRejection за время своего сценария Ж. Вешаем сторожа на весь
 * прогон и после него ждём один оборот очереди микрозадач — только тогда
 * Node успевает решить, был ли у промиса перехватчик.
 */
function прогонСоСторожем(исходник, прогонДанные) {
  return new Promise(function (готово) {
    let непойманныйОтказ = null;
    const сторож = function (причина) { непойманныйОтказ = причина; };
    process.on('unhandledRejection', сторож);
    прогон(исходник, прогонДанные);
    setImmediate(function () {
      process.removeListener('unhandledRejection', сторож);
      прогонДанные.сценарий('Ж. ошибка fetch не бросает исключение');
      прогонДанные.проверить(непойманныйОтказ === null,
        'отклонённый промис fetch перехвачен — необработанного отказа нет (было: ' + непойманныйОтказ + ')');
      готово();
    });
  });
}

/**
 * Сделать копию js/пульс.js во временной папке с указанными текстовыми
 * заменами (одна прицельная поломка на вариант).
 */
function сделатьКопиюСЗаменами(замены, суффикс) {
  let текст = fs.readFileSync(ИСХОДНИК, 'utf8');
  for (const { откуда, куда } of замены) {
    const новыйТекст = текст.split(откуда).join(куда);
    if (новыйТекст === текст) {
      return { ошибка: 'поломка "' + суффикс + '" не применилась: не найден фрагмент ' + JSON.stringify(откуда.slice(0, 70)) + '…' };
    }
    текст = новыйТекст;
  }
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'пульс-сломать-' + суффикс + '-'));
  const файл = path.join(папка, 'пульс.js');
  fs.writeFileSync(файл, текст, 'utf8');
  return { путь: файл, исходник: текст };
}

