async function основной() {
  console.log('=== Проверка js/пульс.js ===');
  const исходникОбычный = fs.readFileSync(ИСХОДНИК, 'utf8');

  if (!СЛОМАТЬ) {
    const прогонДанные = новыйПрогон();
    await прогонСоСторожем(исходникОбычный, прогонДанные);

    console.log('\nИтого проверок: ' + прогонДанные.счёт() + ', провалов: ' + прогонДанные.провалы.length);
    for (const беда of прогонДанные.провалы) console.log('  - ' + беда);
    process.exit(прогонДанные.провалы.length > 0 ? 1 : 0);
    return;
  }

  console.log('\n*** ЛОМАЮЩИЙ ЗАПУСК: по одной поломке во временной копии ***');
  let итогКод = 0;
  for (const вариант of ЛОМАЮЩИЕ_ВАРИАНТЫ) {
    console.log('\n--- Вариант «' + вариант.имя + '»: ' + вариант.поясн + ' ---');
    const копия = сделатьКопиюСЗаменами(вариант.замены, вариант.имя);
    if (копия.ошибка) {
      console.log('  ✗ ' + копия.ошибка);
      итогКод = 1;
      continue;
    }
    const прогонДанные = новыйПрогон();
    await прогонСоСторожем(копия.исходник, прогонДанные);
    const непойманные = вариант.ожидаемые.filter(function (имя) { return !(имя in прогонДанные.провалыПоСценариям); });
    if (непойманные.length > 0) {
      console.log('  ПРОВЕРКА СЛЕПАЯ: копия «' + вариант.имя + '» не покраснела в сценарии ' + непойманные.join(', '));
      итогКод = 1;
    } else {
      console.log('  копия «' + вариант.имя + '» покраснела как положено — проверка рабочая');
    }
  }
  console.log('\nЛомающий запуск завершён, итоговый код: ' + итогКод +
    ' (провалы внутри копий — ожидаемые, это и значит «покраснела»)');
  process.exit(итогКод);
}

основной().catch(function (беда) {
  console.log('ПРОВЕРКА ОБОРВАЛАСЬ: ' + (беда && беда.message));
  console.log(беда && беда.stack);
  process.exit(1);
});
