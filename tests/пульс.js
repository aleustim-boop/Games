/* =====================================================================
   Проверка js/пульс.js — тихий стук браузера «я в игре» для дашборда.

   Файл браузерный (window, document, fetch, setInterval), поэтому
   поднимаем его в песочнице vm с поддельными версиями всего этого.
   Своих узлов и разметки у пульса нет — общий поддельный документ из
   tests/поддельный-браузер.js тут не нужен, песочница собирается прямо
   здесь, минимально под задачу.

   «Часы» этого файла — не Date, а сами интервалы setInterval/clearInterval:
   мы подменяем их своими, которые ничего не ждут взаправду, а копят
   зарегистрированные функции и запускают их по команде тикнуть().
   Так «3 минуты» проверяются мгновенно, без настоящего ожидания.

   Сценарии:
     A. Видима 3 минуты → 4 запроса (0, 60, 120, 180 с).
     Б. Скрыта с самого начала → 0 запросов, таймер не заведён.
     В. Без initData → 0 запросов, даже после нескольких тиков.
     Г. Видима → скрыта → тишина, снова видна → запрос сразу (таймер
        и правда останавливается, а не продолжает тикать в фоне).
     Д. Скрыта с самого начала, потом видна → запрос сразу.
     Е. Тело запроса содержит initData и игру.
     Ж. Ошибка fetch (бросает синхронно и отклоняет промис) не роняет
        запустить() и не оставляет необработанный отказ промиса.

   Ломающий запуск --сломать: две прицельные поломки js/пульс.js во
   временной папке — таймер не останавливается при скрытии (должен
   поймать сценарий Г) и пропавшая проверка initData (должен поймать
   сценарий В).

   Запуск:
       node tests/пульс.js
       node tests/пульс.js --сломать
   ===================================================================== */

