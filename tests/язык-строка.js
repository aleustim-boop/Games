// Проверка: строка «Язык» в окнах страниц без общего листа (js/язык-строка.js).
//
// Запуск:
//   node tests/язык-строка.js                   — обычный прогон, ждём 0 провалов
//   node tests/язык-строка.js --файл <путь>     — тот же набор на копии модуля
//   node tests/язык-строка.js --сломать <папка> — копия модуля с порчей во временной
//     папке обязана покраснеть (три порчи); файл проекта не трогаем
//
// Страницы нет: модуль грузится в песочницу vm с поддельным документом.
// Поддельный документ сам не сообщает о правках, поэтому подложен поддельный
// MutationObserver: проверка запоминает его обработчик и вызывает после каждой
// правки окна — так, как это сделал бы браузер. Какие именно правки ловит
// настоящий наблюдатель (open, childList, subtree), проверяется по его настройкам.
// Ноль найденных узлов — провал, не пропуск.

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { spawnSync } = require('child_process');
const { сделатьДокумент } = require('./поддельный-браузер.js');

const КОРЕНЬ = path.join(__dirname, '..');
const ФАЙЛ = path.join(КОРЕНЬ, 'js', 'язык-строка.js');

function довод(имя) {
  const и = process.argv.indexOf(имя);
  return и !== -1 ? process.argv[и + 1] : null;
}

function сделатьЯзык() {
  const круг = ['ru', 'uk', 'en'];
  const названия = { ru: 'Русский', uk: 'Українська', en: 'English' };
  const я = { код: 'ru', нажатий: 0 };
  я.api = {
    следующий: function () { я.нажатий++; я.код = круг[(круг.indexOf(я.код) + 1) % 3]; return я.код; },
    название: function () { return названия[я.код]; }
  };
  return я;
}

/** Страница: общий поддельный документ, модуль в песочнице, поддельный наблюдатель. */
function страница(путь, сЯзыком) {
  const документ = сделатьДокумент();
  const язык = сделатьЯзык();
  const окно = {};
  if (сЯзыком) окно.ЯзыкИнтерфейса = язык.api;
  const наблюдатель = { обработчик: null, настройки: null, цель: null };
  function ПоддельныйНаблюдатель(обработчик) { наблюдатель.обработчик = обработчик; }
  ПоддельныйНаблюдатель.prototype.observe = function (цель, настройки) { наблюдатель.цель = цель; наблюдатель.настройки = настройки; };
  const песочница = { window: окно, document: документ, setTimeout: setTimeout, module: { exports: {} }, MutationObserver: ПоддельныйНаблюдатель };
  vm.createContext(песочница);
  vm.runInContext(fs.readFileSync(путь, 'utf8'), песочница, { filename: путь });
  return { документ: документ, язык: язык, наблюдатель: наблюдатель, сработать: function () { if (наблюдатель.обработчик) наблюдатель.обработчик([]); } };
}

/** Окно как у страницы: <dialog> с заголовком (в теле или снаружи) и телом. */
function окноСтраницы(с, вид) {
  const д = с.документ;
  const тело = д.узел('div', { id: вид.тело });
  const диалог = д.узел('dialog', { id: 'окно-' + вид.тело });
  if (вид.заголовокСнаружи) диалог.appendChild(д.узел('h2', { id: вид.idЗаголовка }));
  диалог.appendChild(тело);
  д.body.appendChild(диалог);
  return { диалог: диалог, тело: тело, вид: вид, с: с };
}

/** Страница заново наполняет тело, как modal(): заголовок, абзац, кнопки. */
function наполнить(о, заголовок, кнопки) {
  const д = о.с.документ;
  о.тело.replaceChildren();
  if (о.вид.заголовокСнаружи) д.getElementById(о.вид.idЗаголовка).textContent = заголовок;
  else о.тело.appendChild(д.узел('h2', { id: 'dialog-title', текст: заголовок }));
  о.тело.appendChild(д.узел('p', { текст: 'Текст окна' }));
  (кнопки || []).forEach(function (т) { о.тело.appendChild(д.узел('button', { текст: т })); });
}

const строки = function (о) { return о.тело.querySelectorAll('[data-язык-строка]'); };

async function прогон(путь) {
  const итоги = { всего: 0, провалов: 0 };
  const надо = function (условие, что) {
    итоги.всего++;
    if (!условие) { итоги.провалов++; console.log('  ПРОВАЛ: ' + что); } else console.log('  ок: ' + что);
  };
  const ВИД_2048 = { тело: 'dialog-content' };
  const ВИД_СУДОКУ = { тело: 'dialog-body' };
  const ВИД_ПОКЕР = { тело: 'pk-dialog-body', idЗаголовка: 'pk-dialog-title', заголовокСнаружи: true };

  // Окна настроек и справки: строка одна.
  const нужные = [
    ['2048 «Ваш ритм игры»', ВИД_2048, 'Ваш ритм игры', ['Готово']],
    ['2048 «Как играть» (#how)', ВИД_2048, 'Как играть', ['Понятно']],
    ['судоку «Как играть в судоку»', ВИД_СУДОКУ, 'Как играть в судоку', ['Понятно']],
    ['косынка «Как играть: Косынка»', ВИД_СУДОКУ, 'Как играть: Косынка', ['Понятно']],
    ['бастион «Настройки»', ВИД_2048, 'Настройки', []],
    ['покер «За вашим столом»', ВИД_ПОКЕР, 'За вашим столом', ['Как играть', 'В лобби']]
  ];
  for (const [имя, вид, заголовок, кнопки] of нужные) {
    const с = страница(путь, true);
    const о = окноСтраницы(с, вид);
    о.диалог.setAttribute('open', '');
    наполнить(о, заголовок, кнопки);
    с.сработать();
    надо(строки(о).length === 1, имя + ': в окне ровно одна строка (найдено ' + строки(о).length + ')');
    с.сработать();
    надо(строки(о).length === 1, имя + ': повторное срабатывание не дублирует');
    наполнить(о, заголовок, кнопки);
    с.сработать();
    надо(строки(о).length === 1, имя + ': после перезаполнения тела строка снова одна');
  }

  // Открытие без нажатия: окно закрыто — строки нет, поставили open — появилась.
  {
    const с = страница(путь, true);
    const о = окноСтраницы(с, ВИД_2048);
    наполнить(о, 'Ваш ритм игры', ['Готово']);
    с.сработать();
    надо(строки(о).length === 0, 'закрытое окно: строки нет');
    о.диалог.setAttribute('open', '');
    с.сработать();
    надо(строки(о).length === 1, 'поставили атрибут open без нажатия — строка появилась');
    const н = с.наблюдатель.настройки || {};
    надо(с.наблюдатель.цель === с.документ && н.attributes === true && н.childList === true && н.subtree === true &&
      Array.isArray(н.attributeFilter) && н.attributeFilter.indexOf('open') !== -1,
      'наблюдатель смотрит за document: open, childList, subtree');
  }

  // Место: перед последней кнопкой «Готово»/«Понятно»; иначе в конец.
  {
    const с = страница(путь, true);
    const о = окноСтраницы(с, ВИД_2048);
    о.диалог.setAttribute('open', '');
    наполнить(о, 'Ваш ритм игры', ['Готово']);
    с.сработать();
    const дети = о.тело.children;
    надо(дети.length === 4 && дети[2].hasAttribute('data-язык-строка') && дети[3].textContent === 'Готово',
      'строка стоит перед кнопкой «Готово»');
    const с2 = страница(путь, true);
    const о2 = окноСтраницы(с2, ВИД_ПОКЕР);
    о2.диалог.setAttribute('open', '');
    наполнить(о2, 'За вашим столом', ['В лобби']);
    с2.сработать();
    const д2 = о2.тело.children;
    надо(д2[д2.length - 1].hasAttribute('data-язык-строка'), 'последняя кнопка не «Готово»/«Понятно» — строка в конце');
  }

  // Не настройки: итог, подтверждения, подсказка — строки нет.
  const чужие = [
    [ВИД_СУДОКУ, 'Всё на своих местах!'], [ВИД_2048, 'Начать заново?'], [ВИД_ПОКЕР, 'Итоги раздачи'],
    [ВИД_ПОКЕР, 'Новая партия?'], [ВИД_СУДОКУ, 'Подсказка'], [ВИД_2048, 'Продать башню?']
  ];
  for (const [вид, заголовок] of чужие) {
    const с = страница(путь, true);
    const о = окноСтраницы(с, вид);
    о.диалог.setAttribute('open', '');
    наполнить(о, заголовок, ['Понятно']);
    с.сработать();
    надо(строки(о).length === 0, 'окно «' + заголовок + '»: строки нет');
  }

  // Нажатие на строку.
  {
    const с = страница(путь, true);
    const о = окноСтраницы(с, ВИД_2048);
    о.диалог.setAttribute('open', '');
    наполнить(о, 'Настройки', []);
    с.сработать();
    const найдено = строки(о);
    надо(найдено.length === 1, 'для нажатия строка найдена');
    if (найдено.length === 1) {
      const значение = найдено[0].querySelector('.язык-строка__значение');
      надо(значение.textContent === 'Русский' && значение.hasAttribute('data-no-translate'), 'справа «Русский», помечено data-no-translate');
      найдено[0].click();
      надо(с.язык.нажатий === 1 && значение.textContent === 'Українська', 'нажатие зовёт следующий() и меняет подпись');
      надо(строки(о).length === 1, 'после нажатия строка одна');
    }
  }

  // Без языка и без окна — ничего не падает.
  {
    const с = страница(путь, false);
    const о = окноСтраницы(с, ВИД_2048);
    о.диалог.setAttribute('open', '');
    наполнить(о, 'Настройки', []);
    с.сработать();
    надо(строки(о).length === 0, 'без ЯзыкИнтерфейса строки нет');
    const с2 = страница(путь, true);
    с2.сработать();
    надо(с2.документ.querySelectorAll('[data-язык-строка]').length === 0, 'без окна строки нет и ничего не упало');
  }

  console.log('Итого проверок: ' + итоги.всего + ', провалов: ' + итоги.провалов);
  return итоги;
}

const ПОРЧИ = [
  ['убран вызов следующий()', function (т) { return т.replace('window.ЯзыкИнтерфейса.следующий();', ''); }],
  ['убран отбор по заголовку (строка во всех окнах)', function (т) { return т.replace('if (этоНастройки(окна[i])) вставитьВОкно', 'if (true) вставитьВОкно'); }],
  ['убрана проверка «строка уже есть» (дубли)', function (т) { return т.replace("if (тело.querySelector('[' + МЕТКА + ']')) return null;", ''); }],
  ['всегда в конец, не перед «Готово»', function (т) { return т.replace('if (закрытие) тело.insertBefore', 'if (false) тело.insertBefore'); }]
];

async function главное() {
  const папка = довод('--сломать');
  if (папка) {
    fs.mkdirSync(папка, { recursive: true });
    const исходник = fs.readFileSync(ФАЙЛ, 'utf8');
    let всё = true;
    ПОРЧИ.forEach(function (порча, номер) {
      const испорчено = порча[1](исходник);
      if (испорчено === исходник) { console.log('ПЛОХО: порча «' + порча[0] + '» не нашла, что портить'); всё = false; return; }
      const копия = path.join(папка, 'язык-строка-' + номер + '.js');
      fs.writeFileSync(копия, испорчено);
      const р = spawnSync(process.execPath, [__filename, '--файл', копия], { encoding: 'utf8' });
      const покраснела = р.status === 1;
      console.log((покраснела ? 'покраснела: ' : 'ПЛОХО, не покраснела: ') + порча[0]);
      if (!покраснела) всё = false;
    });
    process.exit(всё ? 0 : 1);
  }
  const итоги = await прогон(довод('--файл') || ФАЙЛ);
  process.exit(итоги.провалов ? 1 : 0);
}

главное();
