      const карта = document.createElement('div');
      карта.className = 'карта';
      карта.style.position = 'absolute';
      карта.style.left = '40px';
      карта.style.top = '120px';
      Д.началоКадра();
      Д.узел('проба-замера', () => карта);
      экран.appendChild(карта);
      Д.конецКадра();
      const было = карта.getBoundingClientRect();
      Д.началоКадра();
      Д.узел('проба-замера', () => карта);
      карта.style.left = '240px';
      карта.style.top = '320px';
      Д.конецКадра();
      // Первый кадр полёта: карта обязана стоять там, где была.
