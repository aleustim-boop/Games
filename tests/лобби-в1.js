async function открыть(браузер, ширина, высота, ошибки, предупреждения) {
  const страница = await браузер.newPage({ viewport: { width: ширина, height: высота } });
  await безTelegram(страница);
  страница.on('console', (з) => {
    // Скрипт Telegram стенд не пускает нарочно (безTelegram) — это его отказ, не игры.
    const откуда = (з.location && з.location().url) || '';
    if (з.type() === 'error' && откуда.indexOf('telegram-web-app.js') !== -1) return;
    if (з.type() === 'error') ошибки.push(з.text() + (откуда ? ' @ ' + откуда : ''));
    if (з.type() === 'warning') предупреждения.push(з.text());
  });
  страница.on('pageerror', (о) => ошибки.push('pageerror: ' + (о && о.message)));
  // Страница без ?сервер= стучится на боевой 127.0.0.1:8790 (статистика,
  // рейтинг) и получает ERR_CONNECTION_REFUSED — к делу этой проверки не
  // относится (как в tests/возврат-к-боту-в-браузере.js).
  await перехватить(страница, /^http:\/\/127\.0\.0\.1:8790\//, (путь) =>
    путь.fulfill({ status: 200, contentType: 'application/json; charset=utf-8', body: JSON.stringify({ ок: false }) }));
  // Регистрируем ПОСЛЕ 8790 — «перехватить» отдаёт запрос последнему
  // подходящему правилу, значит этот адрес проверится первым. Примета —
  // РОВНО корень («АДРЕС» как кусок строки поймал бы и «АДРЕС+игры/дурак/game.js»,
  // подменив собой все скрипты страницы).
  if (сломаннаяРазметка) {
    const кореньСтраницы = new RegExp('^' + АДРЕС.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '($|\\?)');
    await перехватить(страница, кореньСтраницы, (путь) =>
      путь.fulfill({ status: 200, contentType: 'text/html; charset=utf-8', body: сломаннаяРазметка }));
  }
  await страница.goto(АДРЕС);
  await страница.waitForFunction(() => typeof настройкиИгрыСБотами !== 'undefined' && typeof путьДурака !== 'undefined');
  await страница.waitForTimeout(400);
  return страница;
}

