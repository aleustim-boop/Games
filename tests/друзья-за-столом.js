function запрос(путь, тело) {
  return new Promise(function (готово) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const req = http.request({
      host: '127.0.0.1', port: ПОРТ, method: 'POST', path: encodeURI(путь),
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let куски = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (к) { куски += к; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(куски); } catch (е) { разобрано = { сырое: куски }; }
        готово({ номер: ответ.statusCode, данные: разобрано, текст: куски });
      });
    });
    req.on('error', function (е) { готово({ номер: 0, данные: { ошибка: String(е.message) }, текст: '' }); });
    req.write(данные);
    req.end();
  });
}

function подписать(поля) {
  const строки = Object.keys(поля).map(function (к) { return к + '=' + поля[к]; }).sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(ТОКЕН).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}

function initDataДля(номер) {
  const поля = {
    query_id: 'AAДрузьяЗаСтолом' + номер,
    user: JSON.stringify({ id: номер, first_name: 'Игрок' + номер }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  поля.hash = подписать(поля);
  return Object.keys(поля)
    .map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(поля[к]); })
    .join('&');
}

function создать(номер, имя, метка, доп) {
  return запрос('/создать', Object.assign({ имя: имя, метка: метка, initData: initDataДля(номер) }, доп));
}

function войти(код, номер, имя, метка) {
  return запрос('/войти', { код: код, имя: имя, метка: метка, initData: initDataДля(номер) });
}

function дверь(код, пропуск, номер) {
  const тело = { код: код, пропуск: пропуск };
  if (номер) тело.initData = initDataДля(номер);
  return запрос('/друзья-за-столом', тело);
}

function позвать(номер, ключ) {
  return запрос('/друзья-позвать', { initData: initDataДля(номер), ключ: ключ });
}

/** Вид стола для игрока — то, что /состояние кладёт в поле «состояние». */
async function видСтола(код, пропуск) {
  const ответ = await запрос('/состояние', { код: код, пропуск: пропуск });
  return ответ.номер === 200 && ответ.данные && ответ.данные.состояние ? ответ.данные.состояние : {};
}

/** Все места ответа двери; пустой список — провал, а не «проверять нечего». */
function местаИз(ответ, надпись) {
  const места = ответ && ответ.данные && Array.isArray(ответ.данные.места) ? ответ.данные.места : [];
  проверить(надпись + ': ответ 200 и список мест непустой', ответ.номер === 200 && места.length > 0,
    'код ' + ответ.номер + ' ' + ответ.текст);
  return места;
}

/** Номера Telegram в теле ответа — только после проверки, что тело непустое. */
function безНомеров(ответ, надпись) {
  const текст = ответ.текст || '';
  проверить(надпись + ': тело ответа непустое', текст.length > 20, 'длина ' + текст.length);
  const найдено = [АНЯ, БОРЯ, ЧУЖОЙ, ЕГОР].filter(function (н) { return текст.indexOf(String(н)) >= 0; });
  проверить(надпись + ': номеров Telegram в ответе нет', текст.length > 20 && найдено.length === 0,
    'нашлись: ' + найдено.join(', '));
}

