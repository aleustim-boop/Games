/* =====================================================================
   «ЗАХВАТ», ЭТАП Р5: войскаДо, доПобеды и выбор «победа» у стола.

   Запуск:
       node tests/захват-сервер-войска-до.js              — проверка настоящих файлов
       node tests/захват-сервер-войска-до.js --сломать    — ломающий прогон на копиях
       node tests/захват-сервер-войска-до.js --папка <копия>  — проверка копии (так её зовёт ломающий прогон)

   Что проверяем (ТЗ 8.5б, 5а, 15.3, К13):
     (1) после разбора у каждого игрока в виде захват.войскаДо = войска на
         начало раунда (числа, тот же порядок областей), а не после разбора;
         расстановка соперника туда не попадает;
     (2) в виде нет чужих черновиков ни под каким ключом;
     (3) до первого разбора войскаДо в виде нет; доПобеды — булево;
     (4) доПобеды true только у стола «до победы»;
     (5) хозяин шлёт 'победа' — комната её запоминает; 'Победа', 0, 50 и
         прочее прежнее значение не меняют.
   Сервер не поднимаем: модули зовутся напрямую в этом же процессе.
   Ломающие прогоны портят КОПИЮ server/ и js/ во временной папке системы.
   ===================================================================== */

const fs = require('fs');
