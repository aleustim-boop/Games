function одинаково(а, б) { return JSON.stringify(а) === JSON.stringify(б); }

/* Есть ли в виде ключ с таким именем на любой глубине. */
function естьКлюч(значение, имя) {
  if (!значение || typeof значение !== 'object') return false;
  return Object.keys(значение).some(function (к) { return к === имя || естьКлюч(значение[к], имя); });
}

function вид(п, место) { return Игра.видДляИгрока(п, место, { код: 'ТЕСТ', этап: 'игра', версия: 1 }).захват; }

function столица(п, место) {
  return п.столицы.find(function (с) { return с.хозяинНаСтарте === место; }).область;
}

/* Черновик, который правила точно примут: всё подкрепление — в свою столицу. */
function поставитьВСтолицу(п, место) {
  const расстановка = {};
  расстановка[столица(п, место)] = п.подкрепление[место];
  return Игра.принятьЧерновик(п, место, { раунд: п.раунд, расстановка: расстановка, приказы: [] });
}

function проверитьВидПослеРазбора() {
  console.log('\n--- (1)–(4) войскаДо и доПобеды в виде ---');
  const игроки = МЕСТА.slice(0, 3);
  const п = Игра.раздать(игроки[0], { игроки: игроки, люди: игроки, хозяин: игроки[0] });

  const свежий = вид(п, игроки[0]);
  проверить(!('войскаДо' in свежий), '(3) до первого разбора войскаДо в виде нет');
  проверить(свежий.доПобеды === false, '(3) доПобеды — булево false у обычного стола: ' + свежий.доПобеды);

  const началоРаунда = п.войска.slice();
  const ответы = игроки.map(function (м) { return поставитьВСтолицу(п, м); });
  проверить(ответы.every(function (о) { return о && о.принято === true; }), '(1) подготовка: три черновика приняты');
  const разбор = Игра.разобратьРаунд(п);
  проверить(разбор && разбор.принято === true, '(1) подготовка: раунд разобран');
  проверить(!одинаково(п.войска, началоРаунда), '(1) подготовка: после разбора войска изменились (иначе проверка не отличит «до» от «после»)');

  игроки.forEach(function (м, номер) {
    const в = вид(п, м);
    проверить(Array.isArray(в.войскаДо) && одинаково(в.войскаДо, началоРаунда),
      '(1) игрок ' + (номер + 1) + ': войскаДо = войскам на начало раунда: ' + JSON.stringify(в.войскаДо));
    проверить(Array.isArray(в.войскаДо) && в.войскаДо.length === в.войска.length && в.войскаДо.every(Number.isInteger),
      '(1) игрок ' + (номер + 1) + ': только целые числа, тот же порядок областей, что у войск');
    проверить(Array.isArray(в.хозяеваДо) && в.хозяеваДо.length === в.войскаДо.length,
      '(1) игрок ' + (номер + 1) + ': войскаДо той же длины, что хозяеваДо');
    проверить(typeof в.доПобеды === 'boolean', '(4) игрок ' + (номер + 1) + ': доПобеды — булево');
    проверить(!естьКлюч(в, 'черновики'), '(2) игрок ' + (номер + 1) + ': в виде нет списка черновиков партии');
  });

  /* Тайна полей (15.3): чужая расстановка в столицу соседа не должна быть видна в «до». */
  const чужаяСтолица = столица(п, игроки[1]);
  проверить(Number.isInteger(чужаяСтолица) && вид(п, игроки[0]).войскаДо[чужаяСтолица] === началоРаунда[чужаяСтолица],
    '(2) войска соседней столицы «до» — как были на начало, без его расстановки');

  // Второй раунд: «до» — это войска, какими раунд 2 начался (после разбора раунда 1).
  const началоВторого = п.войска.slice();
  игроки.forEach(function (м) { поставитьВСтолицу(п, м); });
  Игра.разобратьРаунд(п);
  проверить(одинаково(вид(п, игроки[0]).войскаДо, началоВторого), '(1) после второго разбора войскаДо — начало второго раунда');
}

function проверитьДоПобеды() {
  console.log('\n--- (4) доПобеды у стола «до победы» ---');
  const игроки = МЕСТА.slice(0, 3);
  const п = Игра.раздать(игроки[0], { игроки: игроки, люди: игроки, хозяин: игроки[0], раундовЗахвата: 'победа' });
  проверить(вид(п, игроки[1]).доПобеды === true, '(4) раундовЗахвата «победа» — доПобеды true в виде');
  const число = Игра.раздать(игроки[0], { игроки: игроки, люди: игроки, хозяин: игроки[0], раундовЗахвата: 20 });
  проверить(вид(число, игроки[1]).доПобеды === false, '(4) раундовЗахвата 20 — доПобеды false');
}

function проверитьВыборУСтола() {
  console.log('\n--- (5) хозяин шлёт «победа» ---');
  const создано = комнаты.создатьКомнату('10.77.0.1', { игра: 'захват', имя: 'Аня', мест: 3, телеграм: 820001 });
  проверить(создано.ок === true, '(5) стол «захвата» создан: ' + (создано.причина || ''));
  if (!создано.ок) return;
  const я = комнаты.найтиИгрока(создано.код, создано.пропуск);
  const комната = я && я.комната;
  проверить(!!комната, '(5) комната найдена');
  if (!комната) return;
  const хозяин = я.ктоЯ;
  const слать = function (значение) {
    return комнаты.сделатьХод(комната, хозяин, { действие: 'настройки', раундовЗахвата: значение });
  };

  const принята = слать('победа');
  проверить(принята.принято === true && комната.раундовЗахвата === 'победа', '(5) «победа» принята: ' + JSON.stringify(комната.раундовЗахвата));
  слать(20);
  проверить(комната.раундовЗахвата === 20, '(5) число 20 из списка принимается');
  слать('победа');
  [['Победа', 'строка с большой буквы'], [0, 'ноль'], [50, 'предел 50 — не вариант']].forEach(function (пара) {
    слать(пара[0]);
    проверить(комната.раундовЗахвата === 'победа', '(5) ' + пара[1] + ' — поле не меняется: ' + JSON.stringify(комната.раундовЗахвата));
  });
}

/* Что реально уходит игроку: длина партии из обёртки стола доезжает до вида. */
function проверитьДлинуВВиде() {
  console.log('\n--- (6) длина партии в виде игрока ---');
  const игроки = МЕСТА.slice(0, 3);
  const п = Игра.раздать(игроки[0], { игроки: игроки, люди: игроки, хозяин: игроки[0] });
  const видС = function (значение) {
    const обёртка = { код: 'ТЕСТ', этап: 'игра', версия: 1 };
    if (значение !== undefined) обёртка.раундовЗахвата = значение;
    return Игра.видДляИгрока(п, игроки[1], обёртка);
  };
  проверить(видС(20).раундовЗахвата === 20, '(6) обёртка 20 — игроку приходит 20');
  проверить(видС('победа').раундовЗахвата === 'победа', '(6) обёртка «победа» — игроку приходит «победа»');
  проверить(!('раундовЗахвата' in видС()), '(6) в обёртке поля нет — в виде поля нет');
  проверить(!('раундовЗахвата' in видС(13)) && !('раундовЗахвата' in видС('Победа')),
    '(6) значение не из списка (13, «Победа») в вид не пропускается');
}

