let проверок = 0;
let провалов = 0;
function проверить(условие, текст) {
  проверок++;
  if (условие) { console.log('  ✓ ' + текст); return; }
  провалов++;
  console.log('  ✗ ПРОВАЛ: ' + текст);
}
function итогИВыход() {
  console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
}
function внутри(папка, путь) {
  const относительно = path.relative(папка, путь);
  return !относительно || (!относительно.startsWith('..') && !path.isAbsolute(относительно));
}
function сколькоРаз(текст, кусок) { return текст.split(кусок).length - 1; }

