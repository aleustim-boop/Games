function стук(тело) {
  return fetch(АДРЕС + '/раздача-дня', {
    method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(тело || {})
  }).then(function (о) { return о.json(); });
}
function спросить(хвост) {
  return fetch(АДРЕС + '/раздача-дня' + хвост).then(function (о) { return о.json(); });
}

let всёХорошо = true;
function проверить(что, правда) {
  console.log((правда ? '  ок   ' : '  БЕДА ') + что);
  if (!правда) всёХорошо = false;
}
function запуститьИДождаться(доводы) {
  return new Promise(function (готово) {
    const дитя = spawn('node', доводы, { encoding: 'utf8' });
    let вывод = '';
    дитя.stdout.on('data', function (к) { вывод += к; });
    дитя.on('close', function () { готово(вывод); });
  });
}
function деньСоСдвигом(сдвиг) {
  const д = new Date();
  д.setDate(д.getDate() + сдвиг);
  return раздача.ключДня(д.getTime());
}

async function сервернаяЧасть() {
  console.log('1. Двери сервера');
  раздача.включитьЗапись();
  раздача.забытьВсё();
  const день = раздача.ключДня();

  const а = await стук({ initData: аня, день: день, исход: 'победа', ходов: 20 });
  console.log('   Аня: ' + JSON.stringify(а));
  проверить('Аня записана, место 1, средний 20',
    а.ок === true && а.сыграли === 1 && а.выиграли === 1 && а.среднийХодПобедителей === 20 && а.моёМесто === 1);
  const б = await стук({ initData: боря, день: день, исход: 'поражение', ходов: 15 });
  проверить('Боря записан, место 2', б.ок === true && б.сыграли === 2 && б.моёМесто === 2);
  const в = await стук({ initData: вася, день: день, исход: 'победа', ходов: 30 });
  console.log('   Вася: ' + JSON.stringify(в));
  проверить('Вася: сыграли 3, выиграли 2, средний 25, место 2',
    в.ок === true && в.сыграли === 3 && в.выиграли === 2 && в.среднийХодПобедителей === 25 && в.моёМесто === 2);

  const глазами = await спросить('?день=' + день);
  console.log('   GET без подписи: ' + JSON.stringify(глазами));
  проверить('GET без подписи: сводка есть, места нет',
    глазами.сыграли === 3 && глазами.моёМесто === null && глазами.узналиВас === false);
  const бореГлазами = await спросить('?день=' + день + '&initData=' + encodeURIComponent(боря));
  проверить('GET с подписью Бори: место 3 (после двух победителей)', бореГлазами.моёМесто === 3);

  const повтор = await стук({ initData: аня, день: день, исход: 'поражение', ходов: 5 });
  console.log('   повтор Ани: ' + повтор.причина);
  проверить('повтор отклонён словами, сводка при этом есть, место прежнее',
    повтор.ок === false && /один раз/.test(повтор.причина) && повтор.сыграли === 3 && повтор.моёМесто === 1);
  const безПодписи = await стук({ день: день, исход: 'победа', ходов: 10 });
  проверить('без подписи не пишем, но сводку отдаём',
    безПодписи.ок === false && безПодписи.узналиВас === false && безПодписи.сыграли === 3);
  const будущее = await стук({ initData: гоша, день: деньСоСдвигом(2), исход: 'победа', ходов: 10 });
  console.log('   день +2: ' + будущее.причина);
  проверить('день через два дня — отказ', будущее.ок === false && /далёк/.test(будущее.причина));
  const вчера = await стук({ initData: гоша, день: деньСоСдвигом(-1), исход: 'победа', ходов: 10 });
  проверить('вчерашний день (часовые пояса) — принят, и это другой день',
    вчера.ок === true && вчера.день === деньСоСдвигом(-1) && вчера.сыграли === 1);
  const мусор = await стук({ initData: дима, день: день, исход: 'выиграл', ходов: 10 });
  проверить('незнакомый исход — отказ: ' + мусор.причина, мусор.ок === false);
  const ноль = await стук({ initData: дима, день: день, исход: 'победа', ходов: 0 });
  проверить('ноль ходов — отказ: ' + ноль.причина, ноль.ок === false);
  const ничья = await стук({ initData: дима, день: день, исход: 'ничья', ходов: '25' });
  проверить('ничья и ходы строкой — приняты, место 3 (между победами и поражением)',
    ничья.ок === true && ничья.моёМесто === 3 && ничья.сыграли === 4 && ничья.выиграли === 2);
  const бореТеперь = await стук({ initData: боря, день: день });
  проверить('сводка без исхода (POST): Боря теперь 4-й, ничего не записано',
    бореТеперь.ок === true && бореТеперь.моёМесто === 4 && бореТеперь.сыграли === 4);
  const безДня = await стук({ initData: женя, исход: 'победа', ходов: 10 });
  проверить('без дня — отказ: ' + безДня.причина, безДня.ок === false);
  проверить('номеров в ответах нет',
    [а, б, в, глазами, повтор, ничья].every(function (о) { return JSON.stringify(о).indexOf('9000') === -1; }));

  раздача.дописать();
  const чтение = await запуститьИДождаться(['-e',
    'const р=require(' + JSON.stringify(path.join(КОРЕНЬ, 'server/раздача-дня.js')) + ');' +
    'process.stdout.write(JSON.stringify(р.сводка(' + JSON.stringify(день) + ', 900002)))']);
  console.log('   другой процесс прочитал: ' + чтение);
  let прочитано = null;
  try { прочитано = JSON.parse(чтение); } catch (с) { прочитано = null; }
  проверить('файл прочитан обратно: сыграли 4, выиграли 2, Боря 4-й',
    прочитано && прочитано.сыграли === 4 && прочитано.выиграли === 2 && прочитано.моёМесто === 4);
  return день;
}

async function браузернаяЧасть(день) {
  console.log('2. Дверь Сеть.раздачаДня в имитации страницы');
  const память = new Map();
  const памятьБраузера = {
    getItem: function (к) { return память.has(к) ? память.get(к) : null; },
    setItem: function (к, ч) { память.set(к, String(ч)); },
    removeItem: function (к) { память.delete(к); }
  };
  память.set('server_address', АДРЕС);
  const окно = {
    location: { search: '', protocol: 'http:', href: 'http://127.0.0.1/' },
    localStorage: памятьБраузера, sessionStorage: памятьБраузера,
    addEventListener: function () {}, Telegram: { WebApp: { initData: женя } }
  };
  const страница = { getElementById: function () { return null; }, addEventListener: function () {},
                     querySelectorAll: function () { return []; }, readyState: 'complete' };
  const окружение = {
    window: окно, document: страница, console: { warn: function () {}, log: console.log, error: console.error },
    fetch: fetch, setTimeout: setTimeout, clearTimeout: clearTimeout, setInterval: setInterval,
    clearInterval: clearInterval, URLSearchParams: URLSearchParams, URL: URL,
    AbortController: AbortController, Promise: Promise, JSON: JSON, Date: Date, Math: Math
  };
  окружение.globalThis = окружение;
  vm.runInNewContext(fs.readFileSync(path.join(КОРЕНЬ, 'js/сеть.js'), 'utf8'), окружение, { filename: 'js/сеть.js' });
  проверить('дверь есть', typeof окно.Сеть.раздачаДня === 'function');

  const сводка = await окно.Сеть.раздачаДня({ день: день });
  console.log('   сводка Жене: ' + JSON.stringify(сводка));
  проверить('сводка: сыграли 4, выиграли 2, Женя ещё не играла', сводка.ок && сводка.сыграли === 4 && сводка.моёМесто === null);
  const сдала = await окно.Сеть.раздачаДня({ день: день, исход: 'победа', ходов: 18 });
  console.log('   Женя сдала: ' + JSON.stringify(сдала));
  проверить('Женя записана и стала первой (18 ходов)', сдала.ок === true && сдала.моёМесто === 1 && сдала.сыграли === 5);
  const ещё = await окно.Сеть.раздачаДня({ день: день, исход: 'победа', ходов: 1 });
  проверить('второй раз — отказ с причиной, сводка на месте', ещё.ок === false && ещё.причина.length > 5 && ещё.сыграли === 5);
  окно.Telegram = null;
  const безTelegram = await окно.Сеть.раздачаДня({ день: день, исход: 'победа', ходов: 1 });
  проверить('без Telegram сдать нельзя, причина словами', безTelegram.ок === false && /Telegram/.test(безTelegram.причина));
  const толькоСводка = await окно.Сеть.раздачаДня({ день: день });
  проверить('но сводку без Telegram видно', толькоСводка.ок === true && толькоСводка.сыграли === 5);
  память.set('server_address', 'http://127.0.0.1:8123');
  const молчит = await окно.Сеть.раздачаДня({ день: день });
  проверить('сервер молчит — пустая сводка с причиной: ' + молчит.причина, молчит.ок === false && молчит.сыграли === 0);
}

