/** Копия server/ и js/ во временной папке, в сервер.js вырезаны маршруты. */
function собратьСломанноеКопию() {
  const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'лучший-счёт-http-'));
  const ПАПКА_ДАННЫХ = path.join(КОРЕНЬ, 'server', 'данные');
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(врем, 'server'), {
    recursive: true,
    filter: function (откуда) { return откуда !== ПАПКА_ДАННЫХ && !откуда.startsWith(ПАПКА_ДАННЫХ + path.sep); }
  });
  require('./пути-проекта.js').скопироватьКод(КОРЕНЬ, врем, 'js');
  const файл = path.join(врем, 'server', 'сервер.js');
  const текст = fs.readFileSync(файл, 'utf8');
  const строкиМаршрутов = /^\s*case '\/(билет-счёта|счёт)':.*\r?\n/gm;
  const найдено = (текст.match(строкиМаршрутов) || []).length;
  // Ноль найденного — провал: иначе ломающий запуск ничего бы не сломал.
  if (найдено !== 2) {
    console.log('  ПРОВАЛ в сервер.js не нашлось двух строк маршрутов для порчи, найдено: ' + найдено);
    fs.rmSync(врем, { recursive: true, force: true });
    process.exit(1);
  }
  fs.writeFileSync(файл, текст.replace(строкиМаршрутов, ''), 'utf8');
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: сервер из копии ' + врем + ' без маршрутов /билет-счёта и /счёт');
  return врем;
}

