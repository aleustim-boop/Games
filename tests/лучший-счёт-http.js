async function главное() {
  сервера.оснасткаДляПроверки(ТОКЕН, function () { return { ok: true }; });
  const сервер = сервера.создатьСервер();
  await new Promise(function (готово, беда) {
    сервер.once('error', беда);
    сервер.listen(0, '127.0.0.1', готово);
  });
  ПОРТ = сервер.address().port;
  console.log('Тестовый сервер поднят в этом процессе на порту ' + ПОРТ + ', PID ' + process.pid +
    ' (боевой 8790 не трогаем)');
  try {
    const билет = await билетСчётИРейтинг();
    await повторнаяСдача(билет);
    await играБезСчёта();
    await безПодписи();
    await лишниеПоляИгрыИРежима();
    await плохиеЧисла();
    await старыйРейтингЦел();
  } catch (сбой) {
    провалов++;
    console.log('  ПРОВАЛ проверка упала: ' + (сбой && сбой.stack || сбой));
  } finally {
    await new Promise(function (готово) { сервер.close(готово); });
    сервера.оснасткаДляПроверки();
    убратьВременное();
  }
  // Ноль найденного — провал: без проверок зелёный итог ничего не значит.
  if (всего < 20) {
    провалов++;
    console.log('  ПРОВАЛ выполнено подозрительно мало проверок: ' + всего);
  }
  console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
  process.exit(провалов > 0 ? 1 : 0);
}

главное();
