генератор.захватитьСлучайность();

/* Сколько раздач в одном сравнении. Каждая играется дважды (со сменой
   сторон), то есть партий будет вдвое больше. */
const РАЗДАЧ_ПО_УМОЛЧАНИЮ = 5000;

/* Партия длиннее этого — считаем зависшей. Вчетвером партии длиннее,
   чем вдвоём, поэтому потолок общий и с запасом. */
const ПРЕДЕЛ_ХОДОВ = 900;

/* ОДНО смещение зерна на все уровни и на все сравнения. Раньше их было
   шесть разных, и уровни играли на разных колодах — сравнивать было нечего.
   Менять это число можно, но только целиком: после правки все прежние
   номера раздач перестанут воспроизводиться. */
const СМЕЩЕНИЕ_РАЗДАЧ = 100003;

/* То же смещение, но его можно подменить с командной строки в режиме «дуэль» —
   чтобы повторить тот же замер на ДРУГОМ наборе раздач и убедиться, что число
   не выпало случайно. Меняется только здесь, читается только в «зерноРаздачи». */
let смещениеСейчас = СМЕЩЕНИЕ_РАЗДАЧ;

/* Порог, который штаб считает доказательством усиления бота. */
const ПОРОГ_ДОКАЗАТЕЛЬСТВА = 55;

/* Столько очков из 100 новичок должен набирать хотя бы против «лёгкого»,
   иначе игра стала непроходимой для того, кто её только открыл. */
const ПОРОГ_ОБИДЫ_НОВИЧКА = 3;

/* ---------------------------------------------------------------------
   МАНЕРЫ ИГРЫ. «Манера» — это то, как сторона принимает решения.
   Три манеры берём прямо из игры (уровни соперника), четвёртую —
   «новичок» — пишем здесь: так играет человек, впервые открывший игру.
   --------------------------------------------------------------------- */

/** Манекен-новичок: любой разрешённый ход наугад, иногда без причины пасует. */
function ходНовичка(п, место) {
  const текущая = игра.фаза(п);
  const рука = п.руки[место];

  if (текущая === 'защита') {
    const варианты = [];
    п.стол.forEach(function (пара, номерПары) {
      if (пара.защита) return;
      рука.forEach(function (карта, номерКарты) {
        if (игра.бьёт(карта, пара.атака, п.козырь)) варианты.push([номерПары, номерКарты]);
      });
    });
    if (варианты.length === 0 || Math.random() < 0.2) { игра.объявитьБеру(п); return; }
    const выбор = варианты[Math.floor(Math.random() * варианты.length)];
    игра.отбить(п, выбор[0], выбор[1]);
    return;
  }

  /* Слово вернулось к тому, кто уже сказал «больше не подкидываю»: от него
     нужно одно — закрыть подход. Класть карту он всё равно не вправе.
     Вдвоём такого не бывает, а за столом вчетвером бывает постоянно. */
  if (игра.ужеСпасовал(п, место)) { игра.пас(п, место); return; }

  const годные = [];
  for (let i = 0; i < рука.length; i++) {
    if (игра.можноПоложить(п, рука[i])) годные.push(i);
  }
  if (годные.length === 0 || (текущая !== 'атака' && Math.random() < 0.4)) {
    игра.пас(п, место);
    return;
  }
  игра.положитьВАтаку(п, место, годные[Math.floor(Math.random() * годные.length)]);
}

/** Манера «играть как бот такого-то уровня». */
function ботомУровня(уровень) {
  return function (п, место) { игра.ходБота(п, место, уровень); };
}

const МАНЕРЫ = {
  'новичок': ходНовичка,
  'лёгкий': ботомУровня('лёгкий'),
  'обычный': ботомУровня('обычный'),
  'сложный': ботомУровня('сложный')
};

function манера(имя) {
  if (!МАНЕРЫ[имя]) {
    console.log('Не знаю манеру игры «' + имя + '». Бывают: ' + Object.keys(МАНЕРЫ).join(', '));
    process.exit(2);
  }
  return МАНЕРЫ[имя];
}

/* Чтобы отчёт читался по-русски: «против сложного», а не «против сложный». */
const КОГО = {
  'новичок': 'новичка', 'лёгкий': 'лёгкого', 'обычный': 'обычного', 'сложный': 'сложного'
};
function кого(имя) { return КОГО[имя] || имя; }

