/**
 * Поединок: одни и те же раздачи, каждая играется дважды со сменой сторон.
 * Возвращает очки стороны А (из 100), погрешность и старые числа
 * (победы / поражения / ничьи) — чтобы можно было сверить со старыми отчётами.
 */
function поединок(имяА, имяБ, раздач, застолом) {
  const место = рассадка(застолом);
  const ходА = манера(имяА);
  const ходБ = манера(имяБ);

  const счёт = { победа: 0, поражение: 0, ничья: 0 };
  const очкиЗаРаздачу = [];         // по каждой раздаче: сумма очков А за две партии (от 0 до 2)
  const беды = [];
  const расхождения = [];           // где наш счёт разошёлся со счётом самой игры
  let партийСыграно = 0;
  /* Отдельно копим очки А по каждому раскладу — по ним видно, много ли даёт
     само кресло. Именно эту разницу прежний замер и принимал за силу бота. */
  const поРаскладам = [{ очки: 0, партий: 0 }, { очки: 0, партий: 0 }];

  for (let номер = 1; номер <= раздач; номер++) {
    const зерно = зерноРаздачи(номер);
    let суммаЗаРаздачу = 0;
    let раздачаЦелая = true;

    /* Два расклада: сперва А сидит на первых креслах, потом на вторых.
       Раздача при этом одна и та же — зерно не меняется. */
    for (let расклад = 0; расклад < 2; расклад++) {
      const креслаА = место.кресла[расклад];
      const креслаБ = место.кресла[1 - расклад];
      const ктоГдеСидит = {};
      креслаА.forEach(function (к) { ктоГдеСидит[к] = ходА; });
      креслаБ.forEach(function (к) { ктоГдеСидит[к] = ходБ; });

      const итог = сыгратьПартию(зерно, место.настройки, ктоГдеСидит);
      if (итог.беда) {
        раздачаЦелая = false;
        if (беды.length < 5) {
          беды.push('раздача ' + номер + ' (расклад ' + (расклад + 1) + ', зерно ' + зерно + '): ' + итог.беда);
        }
        continue;
      }
      партийСыграно++;
      const очки = очкиСтороны(итог.партия, креслаА);
      if (!счётСошёлсяСИгрой(итог.партия, креслаА, креслаБ, очки) && расхождения.length < 5) {
        расхождения.push('раздача ' + номер + ' (зерно ' + зерно + '): замер засчитал стороне «' +
          имяА + '» ' + очки + ' очка, а игра говорит про человека «' +
          игра.чемКончилосьДляМеня(итог.партия) +
          '»; дураки: ' + (итог.партия.проигравшие || []).join(' и '));
      }
      суммаЗаРаздачу += очки;
      поРаскладам[расклад].очки += очки;
      поРаскладам[расклад].партий++;
      if (очки === 1) счёт.победа++;
      else if (очки === 0) счёт.поражение++;
      else счёт.ничья++;
    }

    if (раздачаЦелая) очкиЗаРаздачу.push(суммаЗаРаздачу);
  }

  /* Очки в пересчёте на 100: 50 — соперники равны.
     Погрешность считаем ПО РАЗДАЧАМ, а не по партиям: две партии одной
     раздачи — это один опыт с двух сторон, и считать их за два независимых
     было бы враньём в свою пользу (погрешность вышла бы меньше настоящей). */
  const раздачЦелых = очкиЗаРаздачу.length;
  const среднее = раздачЦелых === 0 ? 0
    : очкиЗаРаздачу.reduce(function (с, з) { return с + з; }, 0) / раздачЦелых / 2;
  let разброс = 0;
  for (const з of очкиЗаРаздачу) разброс += (з / 2 - среднее) * (з / 2 - среднее);
  const отклонение = раздачЦелых > 1 ? Math.sqrt(разброс / (раздачЦелых - 1)) : 0;
  const погрешность = раздачЦелых > 1 ? 1.96 * отклонение / Math.sqrt(раздачЦелых) * 100 : 0;

  return {
    А: имяА, Б: имяБ, застолом: застолом,
    подпись: место.подпись,
    раздач: раздачЦелых,
    партий: партийСыграно,
    очки: среднее * 100,
    погрешность: погрешность,
    победа: партийСыграно ? счёт.победа / партийСыграно * 100 : 0,
    поражение: партийСыграно ? счёт.поражение / партийСыграно * 100 : 0,
    ничья: партийСыграно ? счёт.ничья / партийСыграно * 100 : 0,
    /* Сколько очков А набрал, сидя только на первых креслах и только на вторых.
       Если эти два числа заметно разные — кресло само по себе даёт преимущество,
       и замер без смены сторон намерил бы силу бота вместе с силой кресла. */
    очкиНаПервыхКреслах: поРаскладам[0].партий ? поРаскладам[0].очки / поРаскладам[0].партий * 100 : 0,
    очкиНаВторыхКреслах: поРаскладам[1].партий ? поРаскладам[1].очки / поРаскладам[1].партий * 100 : 0,
    беды: беды,
    расхождения: расхождения
  };
}

