/**
 * Слепок стола: по нему видно, сдвинулась ли партия хоть на шаг.
 * Нужен, чтобы поймать ход, который ничего не изменил, — иначе замер
 * крутился бы на месте до потолка ходов и врал бы про «зависание».
 */
function слепок(п) {
  const вРуках = п.игроки.map(function (и) { return (п.руки[и] || []).length; }).join('/');
  const отбитых = п.стол.filter(function (пара) { return пара.защита; }).length;
  return [игра.фаза(п), п.стол.length, отбитых, п.отбой.length, п.колода.length,
          вРуках, п.атакует, (п.пасы || []).join(',')].join('|');
}

/**
 * Сыграть одну партию до конца.
 * «ктоГдеСидит» — на каждое место за столом своя манера игры.
 * Возвращает { партия, беда }: беда не пустая, если партия не доиграна.
 */
function сыгратьПартию(зерно, настройки, ктоГдеСидит) {
  генератор.поставитьЗерно(зерно);
  const п = игра.создатьПартию(настройки);
  let шагов = 0;
  while (!п.завершена && шагов++ < ПРЕДЕЛ_ХОДОВ) {
    const место = игра.ктоХодит(п);
    if (место === null) return { партия: п, беда: 'партия не окончена, а ходить некому' };
    const было = слепок(п);
    ктоГдеСидит[место](п, место);
    if (слепок(п) === было) return { партия: п, беда: 'ход игрока «' + место + '» ничего не изменил' };
  }
  if (!п.завершена) return { партия: п, беда: 'не кончилась за ' + ПРЕДЕЛ_ХОДОВ + ' ходов' };
  return { партия: п, беда: null };
}

/**
 * Сколько очков стороне за эту партию: победа — 1, ничья — 0,5, проигрыш — 0.
 * «Места стороны» — одно кресло в игре вдвоём и два кресла в игре парами.
 */
function очкиСтороны(п, местаСтороны) {
  const проигравшие = п.проигравшие || [];
  if (проигравшие.length === 0) return 0.5;      // дурака нет — ничья
  const мойПроиграл = местаСтороны.some(function (место) {
    return проигравшие.indexOf(место) !== -1;
  });
  return мойПроиграл ? 0 : 1;
}

/**
 * Сверка с самой игрой. Две проверки на каждую партию:
 *
 * 1) Очки двух сторон обязаны в сумме давать ровно 1. Иначе получилось бы,
 *    что проиграли обе стороны разом или не проиграл никто.
 * 2) Сторона, сидящая на месте «человек», должна получить ровно тот же итог,
 *    какой игра засчитывает живому игроку (её функция «чемКончилосьДляМеня»).
 *    Расхождение значит, что замер считает победы не так, как их видит игрок
 *    на экране, — и тогда всем числам грош цена.
 *
 * Вторая проверка стоит здесь нарочно: на этих же граблях уже поскользнулась
 * проверка «как-считается-итог-компанией» — там своя копия подсчёта однажды
 * устарела, и замер начал мерить сам себя.
 */
function счётСошёлсяСИгрой(п, креслаА, креслаБ, очкиА) {
  if (очкиА + очкиСтороны(п, креслаБ) !== 1) return false;
  const сЧеловеком = креслаА.indexOf('человек') !== -1;
  const очкиЧеловека = сЧеловеком ? очкиА : очкиСтороны(п, креслаБ);
  const поИгре = игра.чемКончилосьДляМеня(п);
  const ожидание = поИгре === 'победа' ? 1 : (поИгре === 'поражение' ? 0 : 0.5);
  return ожидание === очкиЧеловека;
}

