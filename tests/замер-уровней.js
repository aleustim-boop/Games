/**
 * Как сидим. Возвращает настройки партии и два набора кресел — по одному
 * на сторону. В игре парами сторона занимает два кресла напротив друг друга.
 */
function рассадка(застолом) {
  if (застолом === 'парами') {
    return {
      настройки: { сложность: 'обычный', игроков: 4, парами: true },
      кресла: [['человек', 'бот-3'], ['бот', 'бот-4']],
      подпись: 'вчетвером парами, колода 36'
    };
  }
  return {
    настройки: 'обычный',                 // уровень партии не важен: манеру задаём каждому месту сами
    кресла: [['человек'], ['бот']],
    подпись: 'вдвоём, колода 36'
  };
}

/** Зерно раздачи по её номеру. Одно и то же для всех сравнений. */
function зерноРаздачи(номер) {
  return (номер * 7919 + смещениеСейчас) | 0;
}

