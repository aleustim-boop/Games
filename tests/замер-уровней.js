/* 2. Насколько неравноправны кресла. Сажаем одну и ту же манеру на оба
      кресла и смотрим, как часто выигрывает то, что сидит первым.
      Первому игра раскладывает руку по порядку, и при равных картах это
      влияет на выбор. Ради этого и введена смена сторон. */
function перекосКресел(раздач) {
  const счёт = { первое: 0, второе: 0, ничья: 0 };
  const ход = манера('обычный');
  for (let номер = 1; номер <= раздач; номер++) {
    const итог = сыгратьПартию(зерноРаздачи(номер), 'обычный',
      { 'человек': ход, 'бот': ход });
    if (итог.беда) continue;
    const очки = очкиСтороны(итог.партия, ['человек']);
    if (очки === 1) счёт.первое++;
    else if (очки === 0) счёт.второе++;
    else счёт.ничья++;
  }
  const всего = счёт.первое + счёт.второе + счёт.ничья;
  if (всего === 0) return { первое: 0, второе: 0, всего: 0, погрешность: 0 };
  const доля = счёт.первое / всего;
  return {
    первое: доля * 100,
    второе: счёт.второе / всего * 100,
    всего: всего,
    /* Насколько такая разница могла выйти просто по везению (95% доверия). */
    погрешность: 1.96 * Math.sqrt(доля * (1 - доля) / всего) * 100 * 2
  };
}
