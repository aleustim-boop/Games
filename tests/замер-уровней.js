/**
 * Сколько раздач просили. Ноль, минус и буквы — это опечатка, а не «сыграй
 * ноль партий»: молча подставлять умолчание нельзя, человек так и не узнает,
 * что его довод не прочли.
 */
function сколькоРаздач(довод) {
  if (довод === undefined) return РАЗДАЧ_ПО_УМОЛЧАНИЮ;
  const н = Number(довод);
  if (!Number.isFinite(н) || Math.floor(н) < 1) {
    console.log('Число раздач должно быть целым и больше нуля, а сказано «' + довод + '».');
    process.exit(2);
  }
  return Math.floor(н);
}

