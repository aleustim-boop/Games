/* =====================================================================
   Независимый замер: чем на самом деле отличаются три уровня соперника.

   Разработчик сообщил доли ничьих 11,8% / 21,8% / 9,4%. Здесь мы меряем
   сами, и не только ничьи, а главное — как часто выигрывает ИГРОК.
   Ведь для человека уровень «сложный» имеет смысл только тогда,
   когда против него реже выигрываешь.

   За человека играют два разных «манекена»:
     «новичок»  — ходит наугад любым разрешённым способом (так играет тот,
                  кто впервые открыл игру);
     «крепкий»  — обычный бот из игры (так играет тот, кто уже освоился).

   Запуск: node tests/замер-уровней.js [партий на каждую пару]
   ===================================================================== */

'use strict';

const игра = require(require('path').join(__dirname, '..', 'js', 'game.js'));

const ПАРТИЙ = Number(process.argv[2]) || 4000;
const ПРЕДЕЛ_ХОДОВ = 500;

let зерно = 1;
Math.random = function () {
  зерно = (зерно * 1103515245 + 12345) % 2147483648;
  return зерно / 2147483648;
};

/** Манекен-новичок: любой разрешённый ход наугад. */
function ходНовичка(п, игрок) {
  const фаза = игра.фаза(п);
  const рука = п.руки[игрок];
  if (фаза === 'защита') {
    const варианты = [];
    п.стол.forEach(function (пара, iП) {
      if (пара.защита) return;
      рука.forEach(function (к, iК) {
        if (игра.бьёт(к, пара.атака, п.козырь)) варианты.push([iП, iК]);
      });
    });
    if (варианты.length === 0 || Math.random() < 0.2) { игра.объявитьБеру(п); return; }
    const в = варианты[Math.floor(Math.random() * варианты.length)];
    игра.отбить(п, в[0], в[1]);
    return;
  }
  const годные = [];
  for (let i = 0; i < рука.length; i++) if (игра.можноПоложить(п, рука[i])) годные.push(i);
  if (годные.length === 0 || (фаза !== 'атака' && Math.random() < 0.4)) { игра.завершитьПодход(п); return; }
  игра.положитьВАтаку(п, игрок, годные[Math.floor(Math.random() * годные.length)]);
}

function ходКрепкого(п, игрок) {
  игра.ходБота(п, игрок, 'обычный');
}

/** Одна партия. Возвращает 'победа' (выиграл человек), 'поражение' или 'ничья'. */
function партия(ходЧеловека, уровеньБота) {
  const п = игра.создатьПартию(уровеньБота);
  let шагов = 0;
  while (!п.завершена && шагов++ < ПРЕДЕЛ_ХОДОВ) {
    const кто = игра.ктоХодит(п);
    if (кто === 'человек') ходЧеловека(п, 'человек');
    else игра.ходБота(п, 'бот', уровеньБота);
  }
  if (!п.завершена) return 'зависла';
  if (п.результат === 'ничья') return 'ничья';
  return п.результат === 'бот' ? 'победа' : 'поражение';
}

/** Погрешность доли при данном числе партий — чтобы не спорить о шуме. */
function погрешность(доля, всего) {
  return 1.96 * Math.sqrt(доля * (1 - доля) / всего) * 100;   // 95% доверия
}

function замер(названиеЧеловека, ходЧеловека, уровеньБота, смещение) {
  const счёт = { победа: 0, поражение: 0, ничья: 0, зависла: 0 };
  for (let н = 1; н <= ПАРТИЙ; н++) {
    зерно = (н * 7919 + смещение) % 2147483648;
    счёт[партия(ходЧеловека, уровеньБота)]++;
  }
  const п = счёт.победа / ПАРТИЙ;
  const н = счёт.ничья / ПАРТИЙ;
  console.log('  соперник «' + уровеньБота + '»: ' +
    'игрок выиграл ' + (п * 100).toFixed(1) + '% (±' + погрешность(п, ПАРТИЙ).toFixed(1) + ') | ' +
    'проиграл ' + (счёт.поражение / ПАРТИЙ * 100).toFixed(1) + '% | ' +
    'ничьих ' + (н * 100).toFixed(1) + '% (±' + погрешность(н, ПАРТИЙ).toFixed(1) + ')' +
    (счёт.зависла ? '  !!! зависших партий: ' + счёт.зависла : ''));
  return { победа: п, ничья: н, зависла: счёт.зависла };
}

console.log('=== Замер трёх уровней соперника ===');
console.log('партий на каждую пару: ' + ПАРТИЙ + ' (в скобках — погрешность, 95% доверия)\n');

console.log('За человека играет НОВИЧОК (ходит наугад):');
const новичок = {};
новичок['лёгкий'] = замер('новичок', ходНовичка, 'лёгкий', 11);
новичок['обычный'] = замер('новичок', ходНовичка, 'обычный', 22);
новичок['сложный'] = замер('новичок', ходНовичка, 'сложный', 33);

console.log('\nЗа человека играет КРЕПКИЙ ИГРОК (обычный бот):');
const крепкий = {};
крепкий['лёгкий'] = замер('крепкий', ходКрепкого, 'лёгкий', 44);
крепкий['обычный'] = замер('крепкий', ходКрепкого, 'обычный', 55);
крепкий['сложный'] = замер('крепкий', ходКрепкого, 'сложный', 66);

console.log('\n--- Вывод простыми словами ---');
function сравнить(кто, набор) {
  const л = набор['лёгкий'].победа, о = набор['обычный'].победа, с = набор['сложный'].победа;
  console.log(кто + ': против лёгкого игрок выигрывает ' + (л * 100).toFixed(1) +
    '%, против обычного ' + (о * 100).toFixed(1) + '%, против сложного ' + (с * 100).toFixed(1) + '%.');
  const шаг = погрешность(о, ПАРТИЙ) + погрешность(с, ПАРТИЙ);
  if (Math.abs(о - с) * 100 < шаг) {
    console.log('  ВНИМАНИЕ: разницы между «обычным» и «сложным» по победам игрока не видно ' +
      '(отличие ' + (Math.abs(о - с) * 100).toFixed(1) + ' процентного пункта при погрешности ' +
      шаг.toFixed(1) + ').');
  }
  if (л <= о) {
    console.log('  ВНИМАНИЕ: против «лёгкого» игрок выигрывает не чаще, чем против «обычного» — ' +
      'уровень не облегчает игру.');
  }
}
сравнить('новичок', новичок);
сравнить('крепкий игрок', крепкий);

let зависших = 0;
for (const набор of [новичок, крепкий]) {
  for (const ключ of Object.keys(набор)) зависших += набор[ключ].зависла;
}
console.log('\nЗависших партий за весь замер: ' + зависших);
process.exit(зависших === 0 ? 0 : 1);
