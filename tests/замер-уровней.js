/* =====================================================================
   ЗАМЕР СИЛЫ СОПЕРНИКА. Насколько «сложный» на самом деле сложнее
   «обычного» — числом, которому можно верить.

   ЗАЧЕМ ФАЙЛ ПЕРЕПИСАН. Владелец игры сказал: «играли на сложном уровне,
   это очень лёгкий противник, мы постоянно выигрываем». Прежний замер
   на это отвечал «разницы между обычным и сложным не видно» — и был
   неправ ЧЕТЫРЕЖДЫ:

   1) Он смотрел только на ПОБЕДЫ игрока. А в дураке кроме побед бывают
      ничьи, и их много. Сложный соперник побеждал почти на 10 пунктов
      чаще обычного — просто потому, что вдвое реже доводил до ничьей.
      Замер этого не видел вовсе и печатал «разницы нет».
      Теперь считаем ОЧКИ, как в спорте: победа — 1, ничья — 0,5.
      Ничья перестала быть невидимкой.

   2) Каждый уровень играл на СВОИХ раздачах (зёрна 11, 22, 33, 44…).
      Половина разницы в цифрах была разницей карт, а не разницей ботов.
      Теперь раздачи у всех уровней одни и те же, до карты.

   3) Кресла за столом не равноправны: игра раскладывает по порядку руку
      только тому, кто сидит первым, а при равных картах порядок в руке
      решает, чем бот сходит. Замер сажал бота всегда на одно кресло.
      Теперь каждая раздача играется ДВАЖДЫ, со сменой сторон.

   4) Мерили только партию вдвоём. Владелец играет ВЧЕТВЕРОМ ПАРАМИ,
      а там сложный бот ведёт себя иначе. Теперь меряем и то, и другое.

   ГЛАВНОЕ ЧИСЛО, которое печатает этот файл, — сколько очков из 100
   набирает «сложный» в прямом поединке с «обычным» на общих раздачах
   со сменой сторон. 50 очков — соперники равны. Доказательством
   усиления бота договорились считать 55 очков и выше.

   ПЯТОЕ, ЧТО ЗАМЕНЕНО ЗАОДНО: генератор случайных чисел. Прежний самодельный
   терял младшие разряды при умножении и повторялся уже через 11 тысяч чисел,
   отчего раздачи ложились неестественно ровно и «погрешность в скобках»
   была посчитана по формуле, к которой эти раздачи не подходили. Теперь
   генератор общий и честный — tests/общий-генератор.js, там же и замеры,
   которыми это доказано. Повторяемость сохранилась: то же зерно — та же
   раздача. Но номера раздач из отчётов ДО этой правки не воспроизводятся.

   Запуск:

     node tests/замер-уровней.js                       полный замер (5000 раздач)
     node tests/замер-уровней.js 1000                  то же, но быстрее и грубее
     node tests/замер-уровней.js дуэль сложный обычный 5000
     node tests/замер-уровней.js дуэль сложный обычный 5000 парами
     node tests/замер-уровней.js дуэль сложный обычный 5000 парами 777
         — последнее число берёт ДРУГОЙ набор раздач: так проверяют,
           не выпало ли число случайно именно на этих картах.

   КОД ВОЗВРАТА. 0 значит «замер отработал честно», а НЕ «с ботом всё
   хорошо». Про бота говорят ТРЕВОГИ в конце вывода — они печатаются
   и при нулевом коде. Ненулевой код бывает, только если сломался сам
   замер: партии не доигрались, счёт разошёлся со счётом игры, смена
   сторон дала не 50 или уровни получили разные раздачи.

   Файл ничего не чинит и ничего в игре не меняет: только играет и считает.
   Библиотек не требует — только сам Node.
   ===================================================================== */

