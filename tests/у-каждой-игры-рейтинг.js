/** Копия страниц корня и папки js/ во временной папке. */
function копияПроекта(имя) {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'у-каждой-игры-' + имя + '-'));
  fs.readdirSync(ПРОЕКТ).filter(function (ф) { return /\.html$/.test(ф); }).forEach(function (ф) {
    fs.copyFileSync(path.join(ПРОЕКТ, ф), path.join(папка, ф));
  });
  fs.cpSync(path.join(ПРОЕКТ, 'js'), path.join(папка, 'js'), { recursive: true });
  return папка;
}

function вставитьПеред(файл, метка, вставка) {
  const т = fs.readFileSync(файл, 'utf8');
  const где = т.lastIndexOf(метка);
  if (где === -1) throw new Error('приём порчи устарел: в ' + файл + ' нет «' + метка + '»');
  fs.writeFileSync(файл, т.slice(0, где) + вставка + т.slice(где), 'utf8');
}

/* Удалить из файла ВСЮ строку, где встретилась метка (ссылка рейтинга
   в страницах игр со счётом лежит на своей строке целиком). */
function убратьСтроку(файл, метка) {
  const т = fs.readFileSync(файл, 'utf8');
  const строки = т.split('\n');
  const оставшиеся = строки.filter(function (с) { return с.indexOf(метка) === -1; });
  if (оставшиеся.length === строки.length) throw new Error('приём порчи устарел: в ' + файл + ' нет строки с «' + метка + '»');
  fs.writeFileSync(файл, оставшиеся.join('\n'), 'utf8');
}

/* Точечная замена подстроки (для правки одного атрибута ссылки). */
function заменитьТекст(файл, что, на) {
  const т = fs.readFileSync(файл, 'utf8');
  if (т.indexOf(что) === -1) throw new Error('приём порчи устарел: в ' + файл + ' нет «' + что + '»');
  fs.writeFileSync(файл, т.split(что).join(на), 'utf8');
}

