/* Для регулярных выражений: ключи игр бывают с дефисом («морской-бой»). */
function экранировать(текст) {
  return текст.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/* Текст без комментариев html и js. Строку «//» после двоеточия или
   кавычки не трогаем — это адрес (https://…), а не комментарий. */
function безКомментариев(текст) {
  return текст
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:'"\\])\/\/[^\n]*/g, '$1');
}

/* Скрипты страницы по порядку: только свои js/…, без хвоста ?v=. */
function скриптыСтраницы(html) {
  const список = [];
  const образец = /<script[^>]*\ssrc="(js\/[^"?]+)(?:\?[^"]*)?"/g;
  let найдено;
  while ((найдено = образец.exec(html)) !== null) список.push(найдено[1]);
  return список;
}

/* Все имена наборов вкладок, названные в тексте страницы и её скриптов. */
function наборыВТексте(текст) {
  const имена = [];
  const образцы = [/data-вкладки="([^"]+)"/g, /вкладкиНабора\(\s*['"]([^'"]+)['"]/g];
  образцы.forEach(function (образец) {
    let найдено;
    while ((найдено = образец.exec(текст)) !== null) имена.push(найдено[1]);
  });
  return имена;
}

/**
 * Проверить один корень (проект или копию). Возвращает счёт и список
 * провалов; печатает построчно, если не «тихо».
 */
function проверитьКорень(КОРЕНЬ, тихо, допДолг) {
  /* допДолг — довесок к ДОЛГу только для этого прогона (сценарий «б»
     ломающего запуска временно дописывает туда игру, которая на самом
     деле уже исправна). В обычном запуске довода нет — работает
     настоящий ДОЛГ без изменений. */
  const эффДолг = Object.assign({}, ДОЛГ, допДолг || {});
  const итог = { проверок: 0, провалы: [], вПорядке: 0, вДолгу: 0, вПорядкеСписок: [] };
  function сказать(т) { if (!тихо) console.log(т); }
  function проверить(условие, текстПровала) {
    итог.проверок++;
    if (!условие) { итог.провалы.push(текстПровала); сказать('  ПРОВАЛ: ' + текстПровала); }
    return условие;
  }
  function прочитать(относительныйПуть) {
    const полный = path.join(КОРЕНЬ, относительныйПуть);
    return fs.existsSync(полный) ? безКомментариев(fs.readFileSync(полный, 'utf8')) : null;
  }

  /* ---- Реестр, вкладки, витрина ---- */
  let реестр = [];
  try {
    const путь = path.join(КОРЕНЬ, 'js', 'игры-реестр.js');
    delete require.cache[path.resolve(путь)];
    реестр = require(путь).все();
  } catch (ошибка) {
    проверить(false, 'не читается js/игры-реестр.js: ' + ошибка.message);
  }
  проверить(реестр.length > 0, 'реестр игр пуст — проверять нечего');
  const записьПоКлючу = {};
  реестр.forEach(function (и) { записьПоКлючу[и.ключ] = и; });

  let вкладкиНабора = null;
  try {
    const путь = path.join(КОРЕНЬ, 'js', 'нижние-вкладки.js');
    delete require.cache[path.resolve(путь)];
    вкладкиНабора = require(путь).вкладкиНабора;
  } catch (ошибка) {
    проверить(false, 'не читается js/нижние-вкладки.js: ' + ошибка.message);
  }

  const витрина = прочитать('index.html');
  проверить(витрина !== null, 'нет index.html');
  const плитки = {};
  (витрина || '').replace(/<(a|button)\s[^>]*data-игра="([^"]+)"[^>]*>/g, function (тег, имяТега, ключ) {
    const ссылка = /href="([^"?]+)/.exec(тег);
    плитки[ключ] = ссылка ? ссылка[1] : null;
    return тег;
  });
  проверить(Object.keys(плитки).length > 0, 'на витрине не найдено ни одной плитки data-игра');

  const страницыКорня = fs.readdirSync(КОРЕНЬ).filter(function (имя) {
    return /\.html$/.test(имя) && !Object.prototype.hasOwnProperty.call(СЛУЖЕБНЫЕ_СТРАНИЦЫ, имя);
  });
  проверить(страницыКорня.length > 0, 'в корне не найдено ни одной страницы *.html');

  /* Каждая страница корня обязана принадлежать какой-то игре реестра. */
  страницыКорня.forEach(function (страница) {
    проверить(реестр.some(function (и) { return и.страница === страница; }),
      'страница ' + страница + ' не принадлежит ни одной игре реестра и не записана в служебные');
  });

  /* ---- Одна игра: чего не хватает, словами. Пусто — в порядке. ---- */
  function чегоНеХватает(ключ) {
    const нет = [];
    const запись = записьПоКлючу[ключ];
    if (!запись) return ['записи в js/игры-реестр.js'];
    if (!Object.prototype.hasOwnProperty.call(плитки, ключ)) нет.push('плитки на витрине');
    else if (плитки[ключ] && плитки[ключ] !== запись.страница) {
      нет.push('совпадения страницы: плитка ведёт на ' + плитки[ключ] + ', в реестре ' + запись.страница);
    }
    if (!запись.вРейтинге) нет.push('места в выборе игры на экране рейтинга (вРейтинге)');
    if (typeof запись.вес !== 'number') нет.push('веса для силы игроков');
    if (!Array.isArray(запись.способОчков) || !запись.способОчков.length) нет.push('способа набрать очки (способОчков пуст)');

    const html = запись.страница ? прочитать(запись.страница) : null;
    if (html === null) {
      нет.push('страницы ' + (запись.страница || '(не указана)'));
      return нет;
    }
    const скрипты = скриптыСтраницы(html);
    if (скрипты.indexOf('js/нижние-вкладки.js') === -1) нет.push('подключения js/нижние-вкладки.js');
    const гдеЭкран = скрипты.indexOf('js/рейтинг-экран.js');
    const гдеРеестр = скрипты.indexOf('js/игры-реестр.js');
    if (гдеЭкран === -1) нет.push('подключения js/рейтинг-экран.js');
    if (гдеРеестр === -1) нет.push('подключения js/игры-реестр.js');
    else if (гдеЭкран !== -1 && гдеРеестр > гдеЭкран) нет.push('js/игры-реестр.js раньше js/рейтинг-экран.js');

    /* Текст страницы и её собственных скриптов. Общие файлы экрана
       рейтинга и вкладок не берём: в них названия игр лежат примерами
       и чужими действиями, они не доказывают, что вход есть у ЭТОЙ страницы. */
    const свои = скрипты.filter(function (с) { return с !== 'js/рейтинг-экран.js' && с !== 'js/нижние-вкладки.js'; });
    const текст = [html].concat(свои.map(function (с) { return прочитать(с) || ''; })).join('\n');

    const наборыСРейтингом = наборыВТексте(текст).map(function (имя) {
      return вкладкиНабора ? вкладкиНабора(имя) : [];
    }).filter(function (вкладки) {
      return вкладки.some(function (в) { return в.подпись === 'Рейтинг'; });
    });
    if (!наборыСРейтингом.length) нет.push('нижней полосы с вкладкой «Рейтинг»');

    const открытие = new RegExp('ЭкранРейтинга\\.открыть\\(\\s*[\'"]' + экранировать(ключ) + '[\'"]\\s*\\)');
    const черезНабор = наборыСРейтингом.some(function (вкладки) {
      return вкладки.some(function (в) { return в.действие === 'рейтинг-' + ключ; });
    });
    if (!открытие.test(текст) && !черезНабор) нет.push('входа в рейтинг именно этой игры (ЭкранРейтинга.открыть(\'' + ключ + '\'))');
    return нет;
  }

  /* ---- Обход ---- */
  const ключи = [];
  function добавить(ключ) { if (ключи.indexOf(ключ) === -1) ключи.push(ключ); }
  реестр.forEach(function (и) { добавить(и.ключ); });
  Object.keys(плитки).forEach(добавить);

  сказать('Корень: ' + КОРЕНЬ);
  сказать('Игр: ' + ключи.length + ' (реестр ' + реестр.length + ', плиток ' + Object.keys(плитки).length +
          ', страниц ' + страницыКорня.length + ')\n');

  ключи.forEach(function (ключ) {
    const нет = чегоНеХватает(ключ);
    const долг = Object.prototype.hasOwnProperty.call(эффДолг, ключ);
    if (!нет.length && !долг) {
      итог.вПорядке++;
      итог.вПорядкеСписок.push(ключ);
      проверить(true, '');
      сказать('ок     ' + ключ);
    } else if (!нет.length && долг) {
      сказать('?      ' + ключ);
      проверить(false, '«' + ключ + '» уже в порядке, но всё ещё в списке ДОЛГ — вычеркните её оттуда');
    } else if (долг) {
      итог.вДолгу++;
      проверить(true, '');
      сказать('долг   ' + ключ + ' — ' + эффДолг[ключ]);
      сказать('         не хватает: ' + нет.join('; '));
    } else {
      сказать('плохо  ' + ключ);
      проверить(false, '«' + ключ + '» без рейтинга, не хватает: ' + нет.join('; '));
    }
  });

  /* Долг за игру, которой нет нигде, — забытая строка: список должен
     только сокращаться, а не хранить мёртвые записи. */
  Object.keys(эффДолг).forEach(function (ключ) {
    проверить(ключи.indexOf(ключ) !== -1, 'в ДОЛГе «' + ключ + '», но такой игры нет ни в реестре, ни на витрине');
  });

  сказать('\nИгр в порядке ' + итог.вПорядке + ', в долгу ' + итог.вДолгу);
  return итог;
}

/* ---------------- Ломающий запуск --сломать ---------------- */

/** Копия страниц корня и папки js/ во временной папке. */
function копияПроекта(имя) {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'у-каждой-игры-' + имя + '-'));
  fs.readdirSync(ПРОЕКТ).filter(function (ф) { return /\.html$/.test(ф); }).forEach(function (ф) {
    fs.copyFileSync(path.join(ПРОЕКТ, ф), path.join(папка, ф));
  });
  fs.cpSync(path.join(ПРОЕКТ, 'js'), path.join(папка, 'js'), { recursive: true });
  return папка;
}

function вставитьПеред(файл, метка, вставка) {
  const т = fs.readFileSync(файл, 'utf8');
  const где = т.lastIndexOf(метка);
  if (где === -1) throw new Error('приём порчи устарел: в ' + файл + ' нет «' + метка + '»');
  fs.writeFileSync(файл, т.slice(0, где) + вставка + т.slice(где), 'utf8');
}

