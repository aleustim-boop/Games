/* Как у других проверок проекта: ломающий запуск печатает найденные
   провалы и выходит с кодом 1. Провалы считаются только ЗАДУМАННЫЕ
   (текст из «ждём») — случайная поломка копии («не читается реестр»)
   за покраснение от порчи не сойдёт, сценарий будет помечен «СЛЕПА». */
function ломающийЗапуск() {
  console.log('Ломающий запуск --сломать: портим КОПИИ во временной папке.\n');
  let проверок = 0;
  let провалов = 0;
  СЦЕНАРИИ.forEach(function (с) {
    const папка = копияПроекта(с.имя);
    const результат = с.выполнить(папка);
    const текст = результат.итог.провалы.join('\n');
    console.log('Сценарий ' + с.имя + ' (' + с.что + '):');
    результат.ждём.forEach(function (ждём) {
      проверок++;
      const строка = результат.итог.провалы.find(function (п) { return п.indexOf(ждём) !== -1; });
      if (строка) { провалов++; console.log('  ПРОВАЛ: ' + строка); }
      else console.log('  СЛЕПА: нет провала «' + ждём + '»; были: ' + (текст || 'ничего'));
    });
    fs.rmSync(папка, { recursive: true, force: true });
  });
  console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
}

