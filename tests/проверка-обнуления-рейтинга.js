'use strict';

/* Проверка: «стереть счёт» переживает молчащее облако.
   Сценарий штаба: очистка при молчащем облаке, потом чтение при ожившем.
   Гоняется на старом файле (слепок из коммита, где ошибка есть) и на новом. */

const fs = require('fs');
const path = require('path');
/* Поддельный браузер — общий (tests/поддельный-браузер.js): память, облако с флагами
   «молчит»/«отказывает», часы, которые переставляют рукой. Своей копии здесь нет. */
const браузер = require('./поддельный-браузер.js');

const НОВЫЙ = fs.readFileSync(path.join(браузер.КОРЕНЬ, 'js', 'telegram.js'), 'utf8');
/* Слепок с ошибкой — из истории git (коммит 20fdaf8), а не копией рядом. */
const СТАРЫЙ = браузер.исходникИзКоммита('20fdaf8', 'js/telegram.js');

const беды = [];
let проверок = 0;
function проверить(условие, что) { проверок++; if (!условие) { беды.push(что); console.log('  ПЛОХО: ' + что); } else { console.log('  ок: ' + что); } }

/* Часы, которые переставляются рукой: чтобы «перерыв после осечки облака» (30 с) прошёл за миг. */
const часы = браузер.поддельныеЧасы(new Date(2026, 8, 7, 12, 0).getTime());
const прошло = (мс) => часы.прошло(мс);

const сделатьПамять = () => браузер.сделатьПамять(false);
/* «молчит» — вообще не отвечает (настоящее ожидание 2,5 с); «отказывает» — сразу
   отвечает ошибкой. И то и другое глушит облако на 30 с. Флаги — у общего облака. */
const сделатьОблако = () => браузер.сделатьОблако({ латиница: false });

function завести(исходник, память, облако) {
  const х = браузер.поднятьTelegramJS({ исходник, память, облако, часы });
  return { Р: х.Рейтинг, память, облако };
}

const тихо = () => new Promise(р => setTimeout(р, 10));
const партийВОблаке = (облако) => { const т = облако.ящик.rating_durak; return т ? JSON.parse(т).всего[0] : null; };

/** Сценарий штаба целиком. молчаОблака: 'молчит' (по-настоящему ждём 2,5 с) или 'отказывает'. */
async function сценарийШтаба(исходник, молчаОблака) {
  const облако = сделатьОблако();
  const телефон = завести(исходник, сделатьПамять(), облако);
  for (let i = 0; i < 3; i++) await телефон.Р.записатьПартию({ исход: 'победа', подпись: 'обычный' });
  const до = await телефон.Р.прочитать('дурак');

  облако[молчаОблака] = true;                       // облако пропало
  const т0 = Date.now();
  const ответОчистки = await телефон.Р.очистить('дурак');
  const ждали = Date.now() - т0;
  облако[молчаОблака] = false;                      // облако ожило
  прошло(31000);                                    // перерыв после осечки прошёл

  const после = await телефон.Р.прочитать('дурак');
  await тихо();                                     // досылке дать дойти
  return { до, ответОчистки, после, облако, телефон, ждали };
}

(async () => {
  console.log('=== 1. Старый файл: ошибка воспроизводится (облако отказывает) ===');
  {
    const р = await сценарийШтаба(СТАРЫЙ, 'отказывает');
    console.log('  до очистки: ' + р.до.всего.партий + '; ответ очистки: ' + р.ответОчистки.всего.партий + '; чтение при ожившем облаке: ' + р.после.всего.партий);
    проверить(р.до.всего.партий === 3 && р.ответОчистки.всего.партий === 0, 'старый файл: до очистки 3, очистка ответила нулём');
    проверить(р.после.всего.партий === 3, 'старый файл: через минуту счёт ВЕРНУЛСЯ из облака (3) — это и есть ошибка');
  }

  console.log('=== 2. Новый файл: облако МОЛЧИТ по-настоящему (ждём 2,5 с) ===');
  {
    const р = await сценарийШтаба(НОВЫЙ, 'молчит');
    console.log('  до очистки: ' + р.до.всего.партий + '; очистка ждала ' + р.ждали + ' мс; чтение при ожившем облаке: ' + р.после.всего.партий + '; в облаке партий: ' + партийВОблаке(р.облако));
    проверить(р.до.всего.партий === 3, 'до очистки 3');
    проверить(р.ответОчистки.всего.партий === 0, 'очистка ответила нулём, не упала');
    проверить(р.после.всего.партий === 0, 'чтение при ожившем облаке — 0, счёт не вернулся');
    проверить(партийВОблаке(р.облако) === 0, 'стирание доехало до облака (досылка)');
    проверить(JSON.parse(р.облако.ящик.rating_durak).обнулено > 0, 'в облаке лежит отметка обнуления');

    // Продолжение: второе устройство со СТАРОЙ памятью (3 партии, без отметки)
    const старая = сделатьПамять();
    старая.setItem('rating_durak', JSON.stringify({ версия: 1, игра: 'дурак', всего: [3, 3, 0, 0], серия: [3, 3], клетки: {}, серии: {}, партии: [], начало: '', обновлено: '' }));
    const планшет = завести(НОВЫЙ, старая, р.облако);
    const наПланшете = await планшет.Р.прочитать('дурак');
    await тихо();
    const записейБыло = р.облако.записей;
    await планшет.Р.прочитать('дурак'); await тихо();
    await планшет.Р.прочитать('дурак'); await тихо();
    console.log('  планшет с памятью «3 партии» читает: ' + наПланшете.всего.партий + '; записей в облако за два лишних чтения: ' + (р.облако.записей - записейБыло));
    проверить(наПланшете.всего.партий === 0, 'планшет со старой памятью тоже видит 0 — стирание общее');
    проверить(р.облако.записей === записейБыло, 'повторные чтения облако не переписывают (нет пинг-понга)');

    const п1 = await планшет.Р.записатьПартию({ исход: 'поражение', подпись: 'сложный' });
    const наТелефоне = await р.телефон.Р.прочитать('дурак');
    console.log('  планшет сыграл партию: ' + п1.всего.партий + '; телефон читает: ' + наТелефоне.всего.партий);
    проверить(п1.всего.партий === 1 && наТелефоне.всего.партий === 1, 'после стирания счёт идёт с нуля на обоих устройствах');
  }

  console.log('=== 3. Новый файл: облако отказывает (быстрый вариант того же) ===');
  {
    const р = await сценарийШтаба(НОВЫЙ, 'отказывает');
    console.log('  чтение при ожившем облаке: ' + р.после.всего.партий);
    проверить(р.после.всего.партий === 0, 'и при отказе облака стирание держится');
  }

  console.log('=== 4. Правила сведения по отдельности ===');
  {
    const запись = (партий, обнулено) => {
      const з = { версия: 1, игра: 'дурак', всего: [партий, партий, 0, 0], серия: [0, 0], клетки: {}, серии: {}, партии: [], начало: '', обновлено: '' };
      if (обнулено) з.обнулено = обнулено;
      return JSON.stringify(з);
    };
    async function свести(вОблаке, вПамяти) {
      const облако = сделатьОблако();
      if (вОблаке) облако.ящик.rating_durak = вОблаке;
      const память = сделатьПамять();
      if (вПамяти) память.setItem('rating_durak', вПамяти);
      const х = завести(НОВЫЙ, память, облако);
      const с = await х.Р.прочитать('дурак');
      await тихо();
      return { партий: с.всего.партий, облако };
    }
    let р;
    р = await свести(запись(100, 0), запись(0, 5000)); проверить(р.партий === 0, 'облако 100 без отметки, память стёрта — 0');
    р = await свести(запись(0, 5000), запись(100, 0)); проверить(р.партий === 0, 'облако стёрто, память 100 без отметки — 0');
    р = await свести(запись(5, 5000), запись(0, 9000)); проверить(р.партий === 0, 'два стирания — позднее побеждает (память)');
    р = await свести(запись(0, 9000), запись(5, 5000)); проверить(р.партий === 0, 'два стирания — позднее побеждает (облако)');
    р = await свести(запись(7, 5000), запись(4, 5000)); проверить(р.партий === 7, 'одно и то же стирание — больше партий, как раньше');
    р = await свести(запись(4, 5000), запись(7, 5000)); проверить(р.партий === 7, '…и в другую сторону');
    р = await свести(запись(7, 0), запись(4, 0)); проверить(р.партий === 7, 'без стираний — больше партий, как раньше');
    р = await свести(запись(4, 0), запись(7, 0)); проверить(р.партий === 7 && партийВОблаке(р.облако) === 7, 'без стираний память больше — досылается в облако');
    р = await свести(null, запись(0, 0)); проверить(р.партий === 0 && партийВОблаке(р.облако) === null, 'совсем пустой счёт в облако не досылаем');
    р = await свести(null, запись(0, 5000)); проверить(р.партий === 0 && р.облако.ящик.rating_durak !== undefined, 'стёртый, но с отметкой — досылаем');
  }

  console.log('=== 5. Отметка не занимает место у тех, кто не стирал ===');
  {
    const х = завести(НОВЫЙ, сделатьПамять(), null);
    await х.Р.записатьПартию({ исход: 'победа', подпись: 'обычный' });
    const текст = х.память.ящик.rating_durak;
    проверить(текст.indexOf('обнулено') < 0, 'в записи без стирания слова «обнулено» нет');
    await х.Р.очистить('дурак');
    проверить(JSON.parse(х.память.ящик.rating_durak).обнулено === часы.сейчас(), 'после стирания отметка — текущее время');
    await х.Р.записатьПартию({ исход: 'победа', подпись: 'обычный' });
    проверить(JSON.parse(х.память.ящик.rating_durak).обнулено === часы.сейчас(), 'новая партия отметку не сбивает');
  }

  console.log('\nпроверок сделано: ' + проверок);
  if (беды.length) { console.log('=== ИТОГ: ЕСТЬ БЕДЫ (' + беды.length + ') ==='); беды.forEach(б => console.log('  - ' + б)); process.exit(1); }
  console.log('=== ИТОГ: стирание счёта переживает молчащее облако ===');
})();
