/* ---------- Прогон ---------- */

function читатьСтраницуКакЕсть(имя) { return fs.readFileSync(path.join(КОРЕНЬ, имя), 'utf8'); }

async function прогнать(пути, порт, только) {
  const краснота = [];
  const текстСети = fs.readFileSync(пути.сеть, 'utf8');
  const исходник = текстСети;
  for (const имя of Object.keys(СЛУЧАИ_С_СЕРВЕРОМ)) {
    if (только && [].concat(только).indexOf(имя) === -1) continue;
    try { await СЛУЧАИ_С_СЕРВЕРОМ[имя](исходник, порт); }
    catch (е) { краснота.push(имя + ': ' + (е && е.message || е)); }
  }
  for (const имя of Object.keys(СЛУЧАИ_ЧТЕНИЯ)) {
    if (только && [].concat(только).indexOf(имя) === -1) continue;
    try { СЛУЧАИ_ЧТЕНИЯ[имя](текстСети, пути.страница); }
    catch (е) { краснота.push(имя + ': ' + (е && е.message || е)); }
  }
  return краснота;
}

const НАСТОЯЩИЕ_ПУТИ = { сеть: НАСТОЯЩАЯ_СЕТЬ, страница: читатьСтраницуКакЕсть };

/* ---------- Порча на копии ---------- */

function путиСПорчей(порча) {
  const файл = порча.файл || 'сеть.js';
  const источник = порча.файл ? path.join(КОРЕНЬ, порча.файл) : НАСТОЯЩАЯ_СЕТЬ;
  const текст = fs.readFileSync(источник, 'utf8');
  const перевод = текст.indexOf('\r\n') !== -1 ? '\r\n' : '\n';
  const было = порча.было.split('\n').join(перевод);
  const стало = порча.стало.split('\n').join(перевод);
  if (сколькоРаз(текст, было) !== 1) return null;
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'мелочи-сети-'));
  const копия = path.join(папка, файл);
  fs.writeFileSync(копия, текст.replace(было, function () { return стало; }));
  const пути = { сеть: НАСТОЯЩАЯ_СЕТЬ, страница: читатьСтраницуКакЕсть, копия: копия };
  if (порча.файл) {
    пути.страница = function (имя) { return имя === порча.файл ? fs.readFileSync(копия, 'utf8') : читатьСтраницуКакЕсть(имя); };
  } else {
    пути.сеть = копия;
  }
  return пути;
}

async function порчаКраснеет(порча, порт) {
  const пути = путиСПорчей(порча);
  if (!пути) { console.log('  порча ' + порча.номер + ': строка не найдена ровно один раз — ' + порча.зачем); return false; }
  const нужные = порча.случаи || [порча.случай];   // «случаи» — краснеть обязаны все названные
  const красное = await прогнать(пути, порт, нужные);
  const поймана = нужные.every(function (имя) { return красное.some(function (с) { return с.indexOf(имя + ':') === 0; }); });
  console.log('  порча ' + порча.номер + ' (' + порча.зачем + '): ' +
    (поймана ? 'красная, как и нужно — ' + красное[0].slice(0, 110) : 'ЗЕЛЁНАЯ — проверка не поймала порчу') + '  [копия: ' + пути.копия + ']');
  return поймана;
}

