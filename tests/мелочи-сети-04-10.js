function свободныйПорт() {
  return new Promise(function (готово, беда) {
    const пробный = net.createServer();
    пробный.once('error', беда);
    пробный.listen(0, ХОСТ, function () {
      const порт = пробный.address().port;
      пробный.close(function () { готово(порт); });
    });
  });
}

function поднятьСервер(порт, папкаДанных) {
  return new Promise(function (готово, беда) {
    const окружение = Object.assign({}, process.env, { GAMES_DATA: папкаДанных });
    const дитя = spawn(process.execPath, [path.join(КОРЕНЬ, 'server', 'сервер.js'), String(порт), '--без-памяти'], { env: окружение });
    let вывод = '';
    const срок = setTimeout(function () { дитя.kill(); беда(new Error('сервер не поднялся за 15 с: ' + вывод)); }, 15000);
    дитя.stdout.on('data', function (кусок) {
      вывод += кусок;
      if (/работает на порту/.test(вывод)) { clearTimeout(срок); готово(дитя); }
    });
    дитя.stderr.on('data', function (кусок) { вывод += кусок; });
    дитя.on('error', беда);
  });
}

