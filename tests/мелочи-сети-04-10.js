/** «/выйти» из старого стола ушёл и сервер его принял (до двух секунд). */
async function выходИзСтарогоДошёл(сцена, порт) {
  const ушёл = await дождаться(function () {
    return сцена.журнал.some(function (з) { return з.путь === '/выйти' && з.тело.код === сцена.старый.код && з.тело.пропуск === сцена.старый.пропуск; });
  }, 3000);
  if (!ушёл) return false;
  let статус = 200;
  for (let п = 0; п < 20 && статус === 200; п++) { статус = await состояниеСтола(порт, сцена.старый); if (статус === 200) await пауза(100); }
  return статус !== 200;
}

