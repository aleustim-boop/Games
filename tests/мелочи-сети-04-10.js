function запись(память) {
  for (const [ключ, значение] of память.ящик) {
    if (ключ.indexOf('room_') === 0) { try { return { ключ: ключ, данные: JSON.parse(значение) }; } catch (с) { return null; } }
  }
  return null;
}

async function дождаться(условие, мс) {
  const до = Date.now() + мс;
  while (Date.now() < до) { if (условие()) return true; await пауза(50); }
  return условие();
}

function ждать(условие, слова) { if (!условие) throw new Error(слова); }

/* Создать стол из лобби (дверью «создатьКомнату», как шаги дурака) и дождаться,
   пока вкладка сядет за него. Кнопкой «Игра с другом» нельзя: при живом
   старом столе она сама возвращает за него, и новый стол создавал бы тот,
   кто уже сидит, — это не тот путь, что рождает призрака. */
async function создатьСтол(вкладка, память, чейКодНеНужен) {
  вкладка.Сеть.создатьКомнату({});
  const сел = await дождаться(function () {
    const з = запись(память);
    return Boolean(з && з.данные.код && з.данные.владелец === вкладка.имя() && з.данные.код !== чейКодНеНужен);
  }, 5000);
  ждать(сел, 'вкладка не создала стол (метки стола в памяти нет — ноль найденного)');
  return запись(память).данные;
}

async function состояниеСтола(порт, стол) {
  const ответ = await fetch('http://' + ХОСТ + ':' + порт + '/состояние', {
    method: 'POST', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ код: стол.код, пропуск: стол.пропуск }) });
  return ответ.status;
}

