async function кодИПропуск(страница) {
  return страница.evaluate(function () {
    try {
      const ключ = Object.keys(window.localStorage).find(function (к) { return к.indexOf('room_') === 0; });
      if (!ключ) return null;
      const запись = JSON.parse(window.localStorage.getItem(ключ) || '{}');
      return запись && запись.код && запись.пропуск ? { код: String(запись.код), пропуск: String(запись.пропуск) } : null;
    } catch (сбой) { return null; }
  });
}

/** Кто сидит за столом. Не нашли комнату — нули (проверка тогда краснеет). */
function составСтола(стол) {
  const найдено = стол ? комнатыСервера().найтиИгрока(стол.код, стол.пропуск) : null;
  const комната = найдено ? найдено.комната : null;
  const сидят = комната ? Object.values(комната.игроки).filter(Boolean) : [];
  return {
    людей: сидят.filter(function (и) { return !и.этоБот; }).length,
    ботов: сидят.filter(function (и) { return и.этоБот; }).length
  };
}

