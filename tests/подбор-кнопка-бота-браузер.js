/* =======================================================================
   Обычный прогон
   ======================================================================= */
async function прогнать(корень) {
  const настоящий = path.resolve(корень).toLowerCase() === path.resolve(ПРОЕКТ).toLowerCase();
  const папкаСнимков = настоящий ? ПАПКА_СНИМКОВ_ПРОЕКТА : path.join(корень, '_снимки-ломающего-прогона');
  fs.mkdirSync(папкаСнимков, { recursive: true });
  КОРЕНЬ_ПРОГОНА = корень;
  console.log('=== Подбор: кнопка «Играть с ботом» — проверка в браузере (playwright) ===');
  console.log('корень: ' + корень + (настоящий ? '' : ' (копия, не проект)'));
  console.log('файлы: ' + АДРЕС_ФАЙЛОВ + ' (не боевой), комнаты: ' + АДРЕС_КОМНАТ + ' (не боевой 8790)');

  const файловый = await поднятьФайловыйСервер(корень, ПОРТ_ФАЙЛОВ);
  let серверКомнат = null;
  let браузер = null;
  try {
    серверКомнат = await поднятьСерверКомнат(корень, ПОРТ_КОМНАТ);
    браузер = await chromium.launch();
    const ошибки = [];
    ошибки.push.apply(ошибки, await сценарий(браузер, path.join(папкаСнимков, 'подбор-кнопка-бота-390.png')));
    ошибки.push.apply(ошибки, await сценарийКнопкаЖдётОтвета(браузер));
    ошибки.push.apply(ошибки, await сценарийДвоеЖивых(браузер));
    ошибки.push.apply(ошибки, await сценарийОтказ429(браузер));
    ошибки.push.apply(ошибки, await сценарийОтменаВоВремяЗапроса(браузер));
    ошибки.push.apply(ошибки, await сценарий320(браузер, path.join(папкаСнимков, 'подбор-кнопка-бота-320.png')));
    console.log('\n-- (и) консоль --');
    проверить(ошибки.length === 0, 'красных ошибок в консоли нет (все страницы)' + (ошибки.length ? ' — ' + ошибки.join(' | ') : ''));
  } finally {
    if (браузер) await браузер.close();
    файловый.kill();
    if (серверКомнат) серверКомнат.close();
    console.log('\nФайловый сервер (' + ПОРТ_ФАЙЛОВ + ') погашен по PID ' + файловый.pid + ', сервер комнат (' + ПОРТ_КОМНАТ + ') закрыт.');
  }

  console.log('\nИтого проверок: ' + всегоПроверок + ', провалов: ' + провалов);
  process.exit(провалов > 0 ? 1 : 0);
}

function доводПосле(имя) {
  const где = process.argv.indexOf(имя);
  return где !== -1 ? process.argv[где + 1] : null;
}

if (process.argv.includes('--сломать')) {
  ломать();
} else {
  const корень = path.resolve(доводПосле('--корень') || ПРОЕКТ);
  прогнать(корень).catch(function (е) {
    console.error('ПРОВАЛ ЗАПУСКА: ' + (е && е.stack || е));
    process.exit(1);
  });
}
