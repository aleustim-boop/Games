/* =======================================================================
   ЛОМАЮЩИЙ ПРОГОН
   ======================================================================= */
function сделатьКопиюПроекта(папка) {
  for (const часть of ['server', 'js', 'img', 'шрифты']) {
    const откуда = path.join(ПРОЕКТ, часть);
    if (!fs.existsSync(откуда)) continue;
    fs.cpSync(откуда, path.join(папка, часть), {
      recursive: true,
      filter: function (файл) {
        const имя = path.basename(файл);
        return имя !== 'данные' && имя !== 'node_modules';
      }
    });
  }
  for (const файл of fs.readdirSync(ПРОЕКТ)) {
    if (файл.endsWith('.html') || файл.endsWith('.css')) {
      fs.copyFileSync(path.join(ПРОЕКТ, файл), path.join(папка, файл));
    }
  }
}

/** Одна порча: копия проекта, правка js/подбор-экран.js, запуск проверки на копию. */
function ломатьОдинРаз(название, найти, заменить, имяФайла) {
  console.log('\n##### Порча: ' + название + ' #####');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'подбор-кнопка-бота-лом-'));
  сделатьКопиюПроекта(папка);
  const файл = path.join(папка, 'js', имяФайла || 'подбор-экран.js');
  const текст = fs.readFileSync(файл, 'utf8');
  /* В файлах бывают и «\n», и «\r\n» (разработчики правят по-разному): если в
     обычном виде строки нет, пробуем с «\r\n» — а не находим по-прежнему нуль. */
  if (текст.indexOf(найти) === -1 && найти.indexOf('\n') !== -1) {
    найти = найти.replace(/\n/g, '\r\n');
    заменить = заменить.replace(/\n/g, '\r\n');
  }
  if (текст.indexOf(найти) === -1) {
    console.log('ПРОВАЛ: в копии js/' + (имяФайла || 'подбор-экран.js') + ' не нашлась строка «' + найти + '» — портить нечего (проверку саму нечем покраснить)');
    return false;
  }
  fs.writeFileSync(файл, текст.split(найти).join(заменить), 'utf8');
  console.log('Порченая копия: ' + папка);

  const прогон = spawnSync(process.execPath, [__filename, '--корень', папка], { encoding: 'utf8', timeout: 240000 });
  const вывод = (прогон.stdout || '').split('\n');
  const плохие = вывод.filter(function (с) { return /ПЛОХО/.test(с); });
  console.log('Красных строк в порченом прогоне: ' + плохие.length + ', код выхода: ' + прогон.status);
  плохие.slice(0, 6).forEach(function (с) { console.log('    ' + с.trim()); });
  if (прогон.stderr) console.log('stderr: ' + прогон.stderr.split('\n').slice(0, 5).join(' | '));
  const покраснел = прогон.status === 1 && плохие.length > 0;
  console.log(покраснел ? 'ПОКРАСНЕЛА, КАК И ДОЛЖНА.' : 'ПРОВАЛ: порча не замечена — проверка не ловит эту поломку!');
  return покраснел;
}

