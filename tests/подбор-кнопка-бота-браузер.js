  отпустить();   // теперь ответ бота доезжает уже после отмены
  await страница.waitForTimeout(3000);
  проверить(!(await доскаШашекВидна(страница)), 'ответ бота после отмены за стол игрока не посадил (доски нет)');
  проверить(!(await видЭкранаОжидания(страница)).экранВиден, 'экран ожидания не воскрес');
  const стол = await кодИПропуск(страница);
  проверить(!стол, 'в памяти браузера нет сохранённой комнаты — за стол не сажали');
  const занятыхМест = комнатыСервера().ктоСейчасЗаСтолом([910008]).size;
  проверить(занятыхМест === 0, 'на сервере игрок не остался за столом с ботом (мест занято: ' + занятыхМест + ')');
