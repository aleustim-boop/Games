async function новаяСтраница(браузер, подпись, ширина) {
  const контекст = await браузер.newContext({ viewport: { width: ширина || ШИРИНА, height: ВЫСОТА } });
  const страница = await контекст.newPage();
  const ошибки = [];
  страница.on('pageerror', function (о) { ошибки.push('исключение: ' + о.message); });
  страница.on('console', function (с) {
    if (с.type() === 'error' && !/Failed to load resource/.test(с.text())) ошибки.push('консоль: ' + с.text());
  });
  await подготовитьПодделку(страница, { подпись: подпись });
  return { контекст: контекст, страница: страница, ошибки: ошибки };
}

async function нажать(страница, id) {
  return страница.evaluate(function (id) {
    const у = document.getElementById(id);
    if (!у) return false;
    у.click();
    return true;
  }, id);
}

async function экранВиден(страница, id) {
  return страница.evaluate(function (id) {
    const у = document.getElementById(id);
    return Boolean(у && у.classList.contains('экран--виден'));
  }, id);
}

/** Всё, что нужно знать про экран ожидания. Узла нет — значения «нет»,
    а не молчаливый пропуск: проверка, не нашедшая кнопку, краснеет. */
async function видЭкранаОжидания(страница) {
  return страница.evaluate(function () {
    function коробка(id) {
      const у = document.getElementById(id);
      if (!у) return { есть: false };
      const р = у.getBoundingClientRect();
      const стиль = window.getComputedStyle(у);
      const видна = !у.classList.contains('скрыт') && у.offsetParent !== null &&
        стиль.visibility !== 'hidden' && р.width > 0 && р.height > 0;
      return {
        есть: true, видна: видна, погашена: Boolean(у.disabled),
        слева: р.left, справа: р.right, сверху: р.top, снизу: р.bottom,
        текст: (у.textContent || '').trim()
      };
    }
    const экран = document.getElementById('экран-подбор-соперника');
    return {
      экранВиден: Boolean(экран && экран.classList.contains('экран--виден')),
      ожидание: коробка('подбор-ожидание'),
      бот: коробка('подбор-с-ботом'),
      отмена: коробка('подбор-отмена'),
      ширинаОкна: window.innerWidth,
      высотаОкна: window.innerHeight,
      прокруткаВбок: document.documentElement.scrollWidth > window.innerWidth
    };
  });
}

function вПределах(к, ширина, высота) {
  return к.есть && к.видна && к.слева >= -0.5 && к.справа <= ширина + 0.5 && к.сверху >= -0.5 && к.снизу <= высота + 0.5;
}

function налезают(а, б) {
  const поГоризонтали = а.слева < б.справа - 0.5 && б.слева < а.справа - 0.5;
  const поВертикали = а.сверху < б.снизу - 0.5 && б.сверху < а.снизу - 0.5;
  return поГоризонтали && поВертикали;
}

