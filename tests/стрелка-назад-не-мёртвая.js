'use strict';

/* =====================================================================
   СТРЕЛКА «НАЗАД» В TELEGRAM НЕ ДОЛЖНА ВИСЕТЬ МЁРТВОЙ.

   Владелец: «Она появилась после того, как я нажал на шахматы, но не
   работает почему-то. В шашках есть, а в дураке нету».

   Что было. Стрелку показывали только шашки и, уходя со страницы,
   не прятали. Стрелка живёт не на странице, а в самом Telegram —
   она переживает переход и остаётся висеть на следующей игре. А
   обработчик, привязанный к ней, умирает вместе со страницей. Человек
   видит кнопку и жмёт в пустоту.

   Проверка ходит дорогой владельца: шашки → витрина → дурак. И держит
   два условия сразу:

     1. стрелка на новой странице либо спрятана, либо РАБОТАЕТ;
     2. на витрине её нет вовсе — назад оттуда некуда, это выход из игры.

   Плюс отдельно проверяется правило, которое чинит беду по устройству:
   дверь сама снимает прежний обработчик, поэтому двух дел на одной
   стрелке не бывает, а «спрятать» отвязывает дело.

   Telegram здесь поддельный: настоящий в проверке не поднять, а нам
   нужно видеть не картинку, а кто на что подписан.

   Запуск:
       node tests/стрелка-назад-не-мёртвая.js
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const КОРЕНЬ = path.join(__dirname, '..');

let проверок = 0;
const провалы = [];

function проверить(условие, что) {
  проверок++;
  if (условие) {
    console.log('  ок   ' + что);
    return;
  }
  провалы.push(что);
  console.log('  ПРОВАЛ: ' + что);
}

/**
 * Поддельный Telegram: помнит, показана ли стрелка и кто на неё подписан.
 * «Нажать» на неё можно прямо отсюда — тем же событием, что и настоящий.
 */
function поддельныйTelegram() {
  const подписки = [];
  const состояние = { стрелкаВидна: false };
  const приложение = {
    version: '7.0',
    isVersionAtLeast: function () { return true; },
    ready: function () {}, expand: function () {},
    initDataUnsafe: {}, themeParams: {},
    CloudStorage: null, HapticFeedback: null,
    BackButton: {
      show: function () { состояние.стрелкаВидна = true; },
      hide: function () { состояние.стрелкаВидна = false; }
    },
    onEvent: function (имя, дело) {
      if (имя === 'backButtonClicked') подписки.push(дело);
    },
    offEvent: function (имя, дело) {
      if (имя !== 'backButtonClicked') return;
      const где = подписки.indexOf(дело);
      if (где !== -1) подписки.splice(где, 1);
    }
  };
  состояние.приложение = приложение;
  состояние.подписки = подписки;
  состояние.нажать = function () {
    for (const дело of подписки.slice()) дело();
  };
  return состояние;
}

/** Поднять js/telegram.js в песочнице с поддельным Telegram. */
function поднятьДверь(телеграм) {
  const исходник = fs.readFileSync(path.join(КОРЕНЬ, 'js', 'telegram.js'), 'utf8');
  const ящик = {};
  const хранилище = {
    getItem: к => (к in ящик ? ящик[к] : null),
    setItem: (к, з) => { ящик[к] = String(з); },
    removeItem: к => { delete ящик[к]; }
  };
  const узел = () => ({
    classList: { add() {}, remove() {}, toggle() {}, contains: () => false },
    addEventListener() {}, setAttribute() {}, appendChild() {},
    style: { setProperty() {}, removeProperty() {} },
    querySelector: () => null, querySelectorAll: () => []
  });
  const окно = {
    Telegram: { WebApp: телеграм.приложение },
    localStorage: хранилище,
    addEventListener() {}, removeEventListener() {},
    matchMedia: () => ({ matches: false, addEventListener() {}, addListener() {} }),
    setTimeout, clearTimeout, setInterval, clearInterval
  };
  const документ = {
    getElementById: () => null, querySelector: () => null, querySelectorAll: () => [],
    createElement: узел, addEventListener() {},
    documentElement: узел(), head: узел(), body: узел()
  };
  const песочница = {
    window: окно, document: документ, localStorage: хранилище,
    console: { log() {}, warn() {}, error() {} },
    setTimeout, clearTimeout, setInterval, clearInterval,
    Math, JSON, Date, Number, String, Array, Object, Boolean, RegExp, Error
  };
  песочница.globalThis = песочница;
  vm.createContext(песочница);
  vm.runInContext(исходник, песочница, { filename: 'js/telegram.js' });
  return окно.Телеграм || null;
}

console.log('=== Стрелка «Назад» ===\n');

console.log('1. Общая дверь есть у всех игр');
const телеграм = поддельныйTelegram();
const дверь = поднятьДверь(телеграм);
проверить(Boolean(дверь), 'window.Телеграм собрался');
проверить(дверь && typeof дверь.показатьСтрелку === 'function', 'есть дверь «показатьСтрелку»');
проверить(дверь && typeof дверь.спрятатьСтрелку === 'function', 'есть дверь «спрятатьСтрелку»');

if (дверь) {
  console.log('\n2. Показали — стрелка видна и делает своё дело');
  let сделано = 0;
  дверь.показатьСтрелку(function () { сделано++; });
  проверить(телеграм.стрелкаВидна === true, 'стрелка показана');
  телеграм.нажать();
  проверить(сделано === 1, 'нажатие дошло до дела страницы');

  console.log('\n3. Второй показ снимает прежнее дело — двух не бывает');
  let второе = 0;
  дверь.показатьСтрелку(function () { второе++; });
  сделано = 0;
  телеграм.нажать();
  проверить(подписокСтолько(телеграм, 1), 'на стрелке ровно одно дело, а не два');
  проверить(сделано === 0 && второе === 1, 'работает новое дело, прежнее отвязано');

  console.log('\n4. Спрятали — стрелки нет и жать нечего');
  второе = 0;
  дверь.спрятатьСтрелку();
  проверить(телеграм.стрелкаВидна === false, 'стрелка спрятана');
  телеграм.нажать();
  проверить(второе === 0, 'дело отвязано: нажимать больше нечего');
  проверить(подписокСтолько(телеграм, 0), 'подписок не осталось ни одной');
}

function подписокСтолько(состояние, сколько) {
  return состояние.подписки.length === сколько;
}

/* ---------------------------------------------------------------------
   Случай владельца: пришёл из шашек, где стрелку показали и не спрятали
   --------------------------------------------------------------------- */

console.log('\n5. Случай владельца: стрелка приехала с чужой страницы');

/* Шашки показали стрелку и ушли. Обработчик страницы умер вместе с ней —
   изображаем это тем, что просто выбрасываем подписку, оставляя стрелку
   показанной: ровно так это выглядит в Telegram. */
const послеШашек = поддельныйTelegram();
послеШашек.приложение.BackButton.show();
послеШашек.подписки.length = 0;

const дверьДурака = поднятьДверь(послеШашек);
проверить(послеШашек.стрелкаВидна === true, 'до начала стрелка висит с прошлой страницы');
проверить(подписокСтолько(послеШашек, 0), 'и она мёртвая: нажимать нечего');

if (дверьДурака) {
  /* Дурак на витрине — стрелку обязан спрятать. */
  дверьДурака.спрятатьСтрелку();
  проверить(послеШашек.стрелкаВидна === false,
    'на витрине чужая стрелка спрятана — мёртвой не висит');

  /* Ушли с витрины внутрь — стрелка появляется и работает. */
  let шагов = 0;
  дверьДурака.показатьСтрелку(function () { шагов++; });
  послеШашек.нажать();
  проверить(послеШашек.стрелкаВидна === true && шагов === 1,
    'на внутреннем экране стрелка есть и делает шаг назад');
}

/* ---------------------------------------------------------------------
   И сам дурак: на витрине прячет, на прочих экранах показывает
   --------------------------------------------------------------------- */

console.log('\n6. Дурак зовёт дверь на каждой смене экрана');
const исходникИгры = fs.readFileSync(path.join(КОРЕНЬ, 'js', 'game.js'), 'utf8');
проверить(исходникИгры.indexOf('освежитьСтрелкуНазад') !== -1,
  'js/game.js знает про стрелку');
проверить(/освежитьСтрелкуНазад\(id\)/.test(исходникИгры),
  'стрелка освежается при смене экрана, а не однажды при запуске');
проверить(/экран-витрины[\s\S]{0,120}спрятатьСтрелку/.test(исходникИгры),
  'на витрине стрелка прячется');

/* ---------------------------------------------------------------------
   Все игры сборника ведут себя одинаково

   Правило владельца: «когда я в шахматы захожу — всё должно быть в едином
   стиле». Значит стрелка не только в дураке: в каждой игре она есть, ведёт
   тот же шаг, что и кнопка «Назад» на экране, и прячется при уходе.

   Читаем сами файлы игр: поднять четыре страницы целиком проверка не может,
   а вот убедиться, что каждая зовёт ОБЩУЮ дверь и прячет стрелку перед
   уходом, — может. Ровно этого шашкам и не хватало.
   --------------------------------------------------------------------- */

console.log('\n7. Стрелка заведена во всех играх, а не только в дураке');

const ИГРЫ = [
  { имя: 'дурак', файл: 'js/game.js' },
  { имя: 'шашки', файл: 'js/шашки-телеграм.js' },
  { имя: 'шахматы', файл: 'js/шахматы-экран.js' },
  { имя: 'нарды', файл: 'js/нарды-экран.js' }
];

for (const игра of ИГРЫ) {
  const текст = fs.readFileSync(path.join(КОРЕНЬ, игра.файл), 'utf8');
  проверить(текст.indexOf('показатьСтрелку') !== -1,
    игра.имя + ': зовёт общую дверь «показатьСтрелку»');
  проверить(текст.indexOf('спрятатьСтрелку') !== -1,
    игра.имя + ': прячет стрелку перед уходом со страницы');
  /* Своего BackButton быть не должно ни у кого: две руки на одной стрелке —
     это и есть та беда, из-за которой обработчик умирал, а кнопка жила. */
  проверить(текст.indexOf('BackButton') === -1,
    игра.имя + ': своего BackButton не держит — стрелка одна на всех');
}

console.log('\n----------------------------------------');
console.log('Проверок сделано: ' + проверок);
if (провалы.length === 0) {
  console.log('ИТОГ: мёртвой стрелке взяться неоткуда.');
  process.exit(0);
}
console.log('ПРОВАЛОВ: ' + провалы.length);
for (const провал of провалы) console.log('  — ' + провал);
process.exit(1);
