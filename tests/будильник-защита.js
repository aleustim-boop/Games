/** Все замены поломки: основная и дополнительные из «ещё». */
function заменыПоломки(поломка) {
  return [{ было: поломка.было, стало: поломка.стало }].concat(поломка.ещё || []);
}

let проверок = 0;
let провалов = 0;

function проверить(условие, что) {
  проверок++;
  if (условие) {
    console.log('  ✓ ' + что);
  } else {
    провалов++;
    console.log('  ✗ ПРОВАЛ: ' + что);
  }
}

/** Кусок с переводами строк того же вида, что в файле (файлы бывают в CRLF). */
function какВФайле(текст, кусок) {
  return текст.indexOf('\r\n') !== -1 ? кусок.split('\n').join('\r\n') : кусок;
}

function сколькоРаз(текст, кусок) {
  return текст.split(какВФайле(текст, кусок)).length - 1;
}

/** Лежит ли путь внутри папки (или совпадает с ней). */
function внутри(папка, путь) {
  const относительно = path.relative(папка, путь);
  return !относительно || (!относительно.startsWith('..') && !path.isAbsolute(относительно));
}

function итогИВыход(код) {
  console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);
  process.exit(код);
}

