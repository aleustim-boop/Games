/** Копия server/ и js/ с одной поломкой; null — поломку не вставить. */
function приготовитьКопию(родитель, номер) {
  const поломка = ПОЛОМКИ[номер];
  const папка = fs.mkdtempSync(path.join(родитель, 'поломка-' + номер + '-'));
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(папка, 'server'), {
    recursive: true,
    filter: function (откуда) {
      const имя = path.basename(откуда);
      return имя !== 'данные' && имя !== 'node_modules';
    }
  });
  fs.cpSync(path.join(КОРЕНЬ, 'js'), path.join(папка, 'js'), { recursive: true });
  const куда = path.join(папка, ФАЙЛ_КОМНАТ);
  const текст = fs.readFileSync(куда, 'utf8');
  if (сколькоРаз(текст, поломка.было) !== 1) return null;
  fs.writeFileSync(куда, текст.split(какВФайле(текст, поломка.было)).join(какВФайле(текст, поломка.стало)));
  return папка;
}

/** Дочерний запуск на копии: ответ { код, провалов, первыйКрасный }. */
function запуститьНаКопии(папка) {
  return new Promise(function (готово) {
    const ребёнок = spawn(process.execPath, [__filename, '--папка', папка], { stdio: ['ignore', 'pipe', 'pipe'] });
    let вывод = '';
    ребёнок.stdout.on('data', function (к) { вывод += к; });
    ребёнок.stderr.on('data', function (к) { вывод += к; });
    ребёнок.on('close', function (код) {
      const итог = вывод.match(/Итого проверок: (\d+), провалов: (\d+)/);
      const первыйКрасный = (вывод.split('\n').find(function (с) { return с.indexOf('✗ ПРОВАЛ') !== -1; }) || '').trim();
      готово({ код: код, провалов: итог ? Number(итог[2]) : 0, итог: итог ? итог[0] : 'итога нет', первыйКрасный: первыйКрасный });
    });
  });
}

async function всеПоломки() {
  const родитель = fs.mkdtempSync(path.join(os.tmpdir(), 'будильник-защита-'));
  let невставлено = 0;
  try {
    const ждём = Object.keys(ПОЛОМКИ).map(async function (номер) {
      const папка = приготовитьКопию(родитель, номер);
      if (!папка) return { номер: номер, невставлено: true };
      return Object.assign({ номер: номер }, await запуститьНаКопии(папка));
    });
    for (const и of await Promise.all(ждём)) {
      const что = 'поломка №' + и.номер + ' (' + ПОЛОМКИ[и.номер].что + ')';
      if (и.невставлено) {
        невставлено++;
        проверить(false, что + ': текст поломки найден в ' + ФАЙЛ_КОМНАТ + ' не ровно один раз — проверка устарела, чините её');
        continue;
      }
      проверить(и.код === 1 && и.провалов > 0, что + ' краснеет: код ' + и.код + ', ' + и.итог +
        (и.первыйКрасный ? ' — ' + и.первыйКрасный.slice(0, 140) : ''));
    }
  } finally {
    // Папка наша и лежит во временной папке системы — её и убираем.
    fs.rmSync(родитель, { recursive: true, force: true });
  }
  итогИВыход(невставлено ? 2 : (провалов ? 1 : 0));
}

