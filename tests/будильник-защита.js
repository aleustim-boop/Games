/* Часы домино — наши: минута на ход проходит, только когда мы её прожили. */
let часы = Date.now();
Д.сейчас = function () { return часы; };

/* Ход по просрочке — подставной: что ответить, решает сценарий. */
const настоящийХод = Д.ходПоПросрочке;
let поведение = null;
let звонки = [];   // время каждого вызова хода по просрочке
Д.ходПоПросрочке = function (п) {
  звонки.push(Date.now());
  return поведение ? поведение(п) : настоящийХод(п);
};

/* «Чей ход» — подставной: сценарий может велеть ему упасть N раз подряд
   (сбой вне хода игры) или падать, пока стоит флаг (сбой уборки). */
const настоящийЧейХод = Д.чейХод;
let чейХодУпадёт = 0;
let чейХодПадает = false;
let чейХодПадаетДля = null;   // партия одной комнаты: падает только у неё
Д.чейХод = function (п) {
  if (чейХодПадает) throw new Error('нарочно: чейХод упал (уборка)');
  if (чейХодПадаетДля && п === чейХодПадаетДля) throw new Error('нарочно: чейХод упал (первая комната)');
  if (чейХодУпадёт > 0) {
    чейХодУпадёт--;
    throw new Error('нарочно: чейХод упал после хода');
  }
  return настоящийЧейХод(п);
};

/* Ход бота — подставной: пока стоит флаг, падает и записывает время. */
const настоящийЗаБота = Д.ходЗаБота;
let ботПадает = false;
let звонкиБота = [];
/* «После хода бота уронить чей ход»: ход удачный, а первый же «чей ход»
   после него падает — сбой ПОСЛЕ хода, а не в нём. */
let послеХодаБотаУронить = false;
Д.ходЗаБота = function (п, кто, уровень) {
  if (ботПадает) {
    звонкиБота.push(Date.now());
    throw new Error('нарочно: ход бота упал');
  }
  const сделано = настоящийЗаБота(п, кто, уровень);
  if (сделано && послеХодаБотаУронить) {
    послеХодаБотаУронить = false;
    чейХодУпадёт = 1;
  }
  return сделано;
};

/* Голос бота — подставной: пока стоит флаг, падает (сбой после хода, до осмотра партии). */
const настоящийГолос = Д.знаки.голосБота;
let голосПадает = false;
Д.знаки.голосБота = function (сделано) {
  if (голосПадает) throw new Error('нарочно: голос бота упал');
  return настоящийГолос(сделано);
};

