const пауза = мс => new Promise(r => setTimeout(r, мс));
async function дождаться(условие, мс) {
  const конец = Date.now() + мс;
  while (Date.now() < конец) { if (условие()) return true; await пауза(5); }
  return условие();
}

let номерАдреса = 0;

/** Стол домино на троих (у домино от трёх мест есть часы); «сБотом» — третье место бот. */
function собратьСтол(сБотом) {
  номерАдреса++;
  const создано = комнаты.создатьКомнату('10.78.0.' + номерАдреса,
    { игра: 'домино', имя: 'Аня', мест: 3, цельДомино: 150, телеграм: 710000 + номерАдреса * 10 });
  if (!создано.ок) throw new Error('комната не создалась: ' + создано.причина);
  const пропуска = [создано.пропуск];
  const люди = сБотом ? ['Боря'] : ['Боря', 'Вера'];
  люди.forEach(function (имя, i) {
    const вход = комнаты.войтиВКомнату(создано.код, { имя: имя, метка: 'budilnik-' + номерАдреса + '-' + i, телеграм: 710000 + номерАдреса * 10 + i + 1 });
    if (!вход.ок) throw new Error('вход не удался: ' + вход.причина);
    пропуска.push(вход.пропуск);
  });
  const найдено = комнаты.найтиИгрока(создано.код, пропуска[0]);
  const комната = найдено.комната;
  if (сБотом) {
    const посадили = комнаты.сделатьХод(комната, найдено.ктоЯ, { действие: 'бот' });
    if (!посадили.принято) throw new Error('бот не сел: ' + посадили.причина);
  }
  if (комната.этап !== 'игра') {
    const ответ = комнаты.сделатьХод(комната, найдено.ктоЯ, { действие: 'начать' });
    if (!ответ.принято) throw new Error('партия не началась: ' + ответ.причина);
  }
  return { код: создано.код, комната: комната, пропуск: пропуска[0] };
}

/** Прожить минуту и позвать уборщика: он перезаведёт будильник, тот сработает сразу. */
function прожитьМинуту() {
  часы += 61000;
  комнаты.прибратьсяСейчас();
}

/** Человек, чья очередь, ходит сам — как его страница. Ответ сервера. */
function ходЧеловека(к) {
  const кто = настоящийЧейХод(к.партия);
  const п = к.партия;
  const ход = п.игра.фаза === 'итог'
    ? { действие: 'раунд' }
    : Б.ход(П.вид(п.игра, п.игроки.indexOf(кто)), 'обычный');
  return комнаты.сделатьХод(к, кто, ход);
}

/** Сценарий в своей комнате: упал — это провал, а не тишина. */
async function сценарий(название, дело) {
  console.log('\n' + название);
  поведение = null;
  звонки = [];
  звонкиБота = [];
  const столы = [];
  try {
    await дело(function (сБотом) { const с = собратьСтол(сБотом); столы.push(с); return с; });
  } catch (сбой) {
    проверить(false, 'сценарий «' + название + '» оборвался: ' + (сбой && сбой.stack));
  } finally {
    поведение = null;
    ботПадает = false;
    чейХодУпадёт = 0;
    чейХодПадает = false;
    чейХодПадаетДля = null;
    послеХодаБотаУронить = false;
    голосПадает = false;
    комнаты.задатьПаузуПослеСбояДляПроверки(ПАУЗА);
    комнаты.остановитьУборку();
    for (const с of столы) комнаты.удалитьКомнату(с.код);
  }
}

/**
 * Довести очередь до бота ходом человека (если первым ходит бот — дождаться
 * его хода и вести дальше). Отдаёт { местоБота, когда } — время последнего
 * хода человека, после которого очередь у бота и заведён таймер бота.
 */
async function довестиДоБота(к) {
  const местоБота = Object.keys(к.игроки).find(м => к.игроки[м].этоБот);
  if (!местоБота) throw new Error('за столом нет бота');
  let когда = null;
  for (let i = 0; i < 60; i++) {
    const кто = настоящийЧейХод(к.партия);
    if (кто === местоБота && когда !== null) return { местоБота: местоБота, когда: когда };
    if (кто === местоБота) {
      const номер = к.номерСобытия;
      if (!await дождаться(() => к.номерСобытия !== номер, 5000)) throw new Error('бот не сходил первым');
      continue;
    }
    const ответ = ходЧеловека(к);
    if (!ответ.принято) throw new Error('ход человека не принят: ' + JSON.stringify(ответ));
    когда = Date.now();
  }
  throw new Error('очередь не дошла до бота');
}

/** Промежутки между попытками: не раньше паузы, а «вовремя» — и не сильно позже. */
function проверитьПромежутки(имя, времена, иНеПозже) {
  const промежутки = времена.slice(1).map((т, i) => т - времена[i]);
  проверить(промежутки.length > 0 && промежутки.every(п => п >= ПАУЗА - 30),
    имя + ': повтор не раньше паузы ' + ПАУЗА + ' мс: ' + JSON.stringify(промежутки));
  if (иНеПозже) {
    проверить(промежутки.length > 0 && промежутки.every(п => п <= ПАУЗА + 150),
      имя + ': повтор вовремя — не позже ' + (ПАУЗА + 150) + ' мс: ' + JSON.stringify(промежутки));
  }
}

/**
 * Три неудачи подряд на одной очереди: после первой будильник перезаведён,
 * повтор не раньше паузы, после третьей — не заводится ни своим повтором,
 * ни уборщиком; стол не тронут и жив.
 */
async function триНеудачи(с, имя) {
  const к = с.комната;
  const звонковДо = звонки.length;
  const номерДо = к.номерСобытия;
  const журналаДо = журнал.length;
  прожитьМинуту();
  проверить(await дождаться(() => звонки.length >= звонковДо + 1, 2000), имя + ': будильник сработал');
  проверить(вылетело.length === 0, имя + ': исключение не вылетело из будильника наружу (вылетело: ' + вылетело.length + ')');
  проверить(Boolean(к.таймерПросрочки), имя + ': после первой неудачи будильник перезаведён');

  await дождаться(() => звонки.length >= звонковДо + ПОПЫТОК, ПАУЗА * ПОПЫТОК * 4);
  await пауза(ПАУЗА * 3);   // четвёртой попытки быть не должно
  const наш = звонки.slice(звонковДо);
  проверить(наш.length === ПОПЫТОК, имя + ': попыток ровно ' + ПОПЫТОК + ': ' + наш.length);
  проверитьПромежутки(имя, наш, false);
  проверить(!к.таймерПросрочки, имя + ': после ' + ПОПЫТОК + ' неудач будильник не заведён');

  // Уборщик тоже не заводит будильник на этой очереди.
  комнаты.прибратьсяСейчас();
  await пауза(ПАУЗА * 3);
  проверить(звонки.length === звонковДо + ПОПЫТОК && !к.таймерПросрочки,
    имя + ': уборщик после ' + ПОПЫТОК + ' неудач будильник не заводит: попыток ' + (звонки.length - звонковДо));

  проверить(к.номерСобытия === номерДо && к.этап === 'игра', имя + ': стол не тронут, партия идёт');
  проверить(Boolean(комнаты.найтиИгрока(с.код, с.пропуск)), имя + ': комната жива');
  проверить(вылетело.length === 0, имя + ': за все попытки наружу не вылетело ни одного исключения');
  const записи = журнал.slice(журналаДо);
  проверить(записи.some(з => з.indexOf('стол ждёт хода человека') !== -1),
    имя + ': после ' + ПОПЫТОК + ' неудач запись в журнале «стол ждёт хода человека»');
  return записи;
}

