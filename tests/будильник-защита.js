    проверить(звонки.length === 1, 'после хода: повтора хода не было: ' + звонки.length);
    поведение = null;
    комнаты.прибратьсяСейчас();
    проверить(Boolean(к.таймерПросрочки) && к.этап === 'игра', 'после хода: уборщик снова завёл будильник, партия идёт');
