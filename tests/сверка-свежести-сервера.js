/* =====================================================================
   Общая утилита: сверить, из какого коммита поднят сервер на указанном
   адресе, с тем коммитом, что сейчас лежит в этой рабочей папке.

   Зачем: сетевые проверки стучатся на порт и верят первому же ответу —
   а на порту может висеть забытая копия сервера трёхдневной давности.
   11 сентября именно так tests/чужой-бой-по-шагам.js трижды соврал
   «ПЛОХО» на устаревшем коде вместо честного «сервер не тот».

   Эта утилита сама ничего не проверяет и не печатает — только отвечает
   на вопрос «тот ли это сервер». Подключение к конкретным проверкам —
   отдельная работа, здесь только готовая функция.

   Использование:
     const { свежийЛиСервер } = require('./сверка-свежести-сервера.js');
     const итог = await свежийЛиСервер('http://127.0.0.1:8790');
     if (итог.свежий === false) console.log('ВНИМАНИЕ: ' + итог.слова);
   ===================================================================== */

'use strict';

const path = require('path');
const { execSync } = require('child_process');

/**
 * Спрашивает /здоровье у сервера и сравнивает присланный коммит
 * с git rev-parse HEAD в текущей рабочей папке.
 *
 * @param {string} адресКомнат — например, 'http://127.0.0.1:8790'
 * @returns {Promise<{свежий: boolean|null, коммитСервера: string|null,
 *                     коммитЗдесь: string|null, слова: string}>}
 */
async function свежийЛиСервер(адресКомнат) {
  // Свой коммит — сверяем всегда, он не зависит от сервера.
  let коммитЗдесь = null;
  try {
    коммитЗдесь = execSync('git rev-parse HEAD', {
      cwd: path.join(__dirname, '..'),
      encoding: 'utf8'
    }).trim();
  } catch (ошибка) {
    коммитЗдесь = null;
  }

  // Коммит сервера — спрашиваем по сети, сервер мог не ответить вовсе.
  let коммитСервера = null;
  let сетеваяБеда = null;
  try {
    const ответ = await fetch(адресКомнат.replace(/\/+$/, '') + '/здоровье', {
      signal: AbortSignal.timeout(10000)
    });
    const данные = await ответ.json();
    коммитСервера = данные && данные.коммит ? String(данные.коммит) : null;
  } catch (сбой) {
    сетеваяБеда = String(сбой && сбой.message || сбой);
  }

  if (сетеваяБеда) {
    return {
      свежий: null,
      коммитСервера: null,
      коммитЗдесь,
      слова: 'сервер на ' + адресКомнат + ' не ответил: ' + сетеваяБеда
    };
  }
  if (!коммитСервера) {
    return {
      свежий: null,
      коммитСервера: null,
      коммитЗдесь,
      слова: 'сервер не сообщил коммит (старая версия без этого поля, либо сам не смог узнать свой git)'
    };
  }
  if (!коммитЗдесь) {
    return {
      свежий: null,
      коммитСервера,
      коммитЗдесь: null,
      слова: 'не удалось узнать свой коммит (git rev-parse не сработал в этой папке)'
    };
  }

  if (коммитСервера === коммитЗдесь) {
    return {
      свежий: true,
      коммитСервера,
      коммитЗдесь,
      слова: 'сервер поднят из того же коммита, что и рабочая папка'
    };
  }
  return {
    свежий: false,
    коммитСервера,
    коммитЗдесь,
    слова: 'сервер поднят из другого коммита (' + коммитСервера.slice(0, 12) +
      '), в рабочей папке сейчас ' + коммитЗдесь.slice(0, 12) +
      ' — похоже на забытую старую копию'
  };
}

module.exports = { свежийЛиСервер };
