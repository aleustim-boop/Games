/* ------------------------------------------------------------------
   Ломающий режим
   ------------------------------------------------------------------ */
function сломать() {
  console.log('=== Ломающий режим: страница получает КОПИЮ игры/захват/захват-онлайн.js без отправки черновика ===');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'захват-онлайн-лом-'));
  let покраснело = false;
  try {
    const текст = fs.readFileSync(path.join(ПРОЕКТ, 'игры', 'захват', 'захват-онлайн.js'), 'utf8');
    const было = 'return window.Сеть.отправитьЧерновик(раунд, черновик).then(ответ => {';
    const части = текст.split(было);
    if (части.length !== 2) throw new Error('в игры/захват/захват-онлайн.js место поломки нашлось ' + (части.length - 1) + ' раз(а), нужно ровно один');
    const копия = path.join(папка, 'захват-онлайн.js');
    fs.writeFileSync(копия, части.join('return Promise.resolve({ принято: true }).then(ответ => {'), 'utf8');
    console.log('копия: ' + копия);
    spawnSync(process.execPath, [path.join(ПРОЕКТ, 'штаб', 'браузер-занят.js'), '--ждать'], { encoding: 'utf8', timeout: 1300000 });
    const р = spawnSync(process.execPath, [__filename, '--прогон', '--подмена', копия, '--порт-комнат', String(ПОРТ_КОМНАТ_ЛОМ), '--порт-файлов', String(ПОРТ_ФАЙЛОВ_ЛОМ),
      '--снимки', path.join(папка, 'снимки')], { encoding: 'utf8', timeout: 480000 });
    const вывод = (р.stdout || '') + (р.stderr || '');
    const красные = ((вывод.match(/КРАСНЫЕ: (.*)/) || [])[1] || '').split(' ## ');
    const нужные = ['Р1. Войска дошли до разбора', 'В3. После возврата приказы Б на месте'];
    const нет = нужные.filter(н => !красные.includes(н));
    покраснело = р.status === 1 && нет.length === 0;
    console.log('выход: ' + р.status + '; красные шаги: ' + красные.join(' | '));
    console.log(покраснело ? '→ ПОКРАСНЕЛА, как и должна (на шагах про приказы)' : '→ ОЖИДАЛОСЬ красное на: ' + нужные.join(' и ') + '; не покраснели: ' + нет.join(', '));
    if (!покраснело) console.log('----- вывод -----\n' + вывод.split('\n').slice(-40).join('\n'));
  } catch (е) {
    console.log('не удалось прогнать поломку: ' + е.message);
  } finally {
    fs.rmSync(папка, { recursive: true, force: true });
  }
  console.log('\nПоломок: 1, покраснело: ' + (покраснело ? 1 : 0));
  process.exitCode = покраснело ? 0 : 1;
}

if (естьДовод('--сломать')) {
  сломать();
} else {
  прогнать().catch(е => { console.error(е); process.exitCode = 1; });
}
