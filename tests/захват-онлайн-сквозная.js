      с.on('console', м => {
        if (м.type() !== 'error') return;
        const адр = (() => { try { return м.location().url || ''; } catch (_) { return ''; } })();
        if (/telegram-web-app/.test(адр) || /telegram-web-app/.test(м.text())) return;
        ошибки.push(метки[i] + ': ' + м.text() + (адр ? ' (' + адр + ')' : ''));
      });
