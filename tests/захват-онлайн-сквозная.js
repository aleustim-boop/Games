/** Порт свободен? Чужая копия на порту — ложь проверки: занято — не начинаем. */
function портСвободен(порт) {
  return new Promise(ответ => {
    const с = net.connect({ port: порт, host: '127.0.0.1' });
    с.on('connect', () => { с.destroy(); ответ(false); });
    с.on('error', () => ответ(true));
  });
}

function поднятьСерверКомнат(корень, порт) {
  const п = spawn(process.execPath, [__filename, '--сервер', '--корень', корень, '--порт-комнат', String(порт)], { stdio: ['ignore', 'pipe', 'pipe'] });
  return new Promise((готово, беда) => {
    let вывод = '';
    const т = setTimeout(() => беда(new Error('сервер комнат не поднялся за 10 с. Вывод: ' + вывод)), 10000);
    п.stdout.on('data', д => { вывод += д.toString(); if (вывод.includes('работает')) { clearTimeout(т); готово(п); } });
    п.stderr.on('data', д => { вывод += д.toString(); });
    п.on('exit', код => { clearTimeout(т); беда(new Error('сервер комнат завершился (код ' + код + '). Вывод: ' + вывод)); });
  });
}

function поднятьФайловыйСервер(корень, порт) {
  const п = spawn(process.execPath, [path.join(ПРОЕКТ, 'tests', 'локальный-сервер.js'), String(порт)], {
    env: Object.assign({}, process.env, { КОРЕНЬ_СЕРВЕРА: корень }), stdio: 'pipe'
  });
  return new Promise((готово, беда) => {
    let вывод = '';
    const т = setTimeout(() => беда(new Error('файловый сервер не поднялся за 8 с')), 8000);
    п.stdout.on('data', д => { вывод += д.toString(); if (вывод.includes('запущен')) { clearTimeout(т); готово(п); } });
    п.on('error', е => { clearTimeout(т); беда(е); });
  });
}

function погасить(п) {
  if (!п || п.killed) return;
  try { п.removeAllListeners('exit'); } catch (_) { /* уже нечего */ }
  try { п.kill(); } catch (_) { /* уже погас */ }
}

