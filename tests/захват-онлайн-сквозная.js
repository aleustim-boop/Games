function утв(условие, увидели) { if (!условие) throw new Провал(увидели); }

async function шаг(имя, ждали, функция) {
  let увидели = '';
  let ок = true;
  try {
    const р = await функция();
    увидели = typeof р === 'string' ? р : '';
  } catch (е) {
    ок = false;
    увидели = е instanceof Провал ? е.message : 'сбой проверки: ' + (е && е.message ? е.message.split('\n')[0] : е);
  }
  итоги.push({ имя, ждали, увидели, ок });
  console.log((ок ? '  ок     ' : '  ПРОВАЛ ') + имя + '\n         ждали:   ' + ждали + '\n         увидели: ' + увидели);
  return ок;
}

function замечание(имя, текст) {
  замечания.push(имя + ': ' + текст);
  console.log('  ЗАМЕЧАНИЕ ' + имя + ': ' + текст);
}

async function ждать(условие, мс) {
  const до = Date.now() + (мс || 6000);
  let последнее = null;
  for (;;) {
    try { последнее = await условие(); } catch (_) { последнее = null; }
    if (последнее) return последнее;
    if (Date.now() > до) return null;
    await пауза(150);
  }
}

