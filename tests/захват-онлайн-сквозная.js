const виден = (с, селектор) => с.evaluate(сел => {
  const у = document.querySelector(сел);
  if (!у) return false;
  const р = у.getBoundingClientRect();
  const ст = getComputedStyle(у);
  return р.width > 0 && р.height > 0 && ст.visibility !== 'hidden' && ст.display !== 'none' && !у.classList.contains('скрыт');
}, селектор);

const текстУзла = (с, селектор) => с.evaluate(сел => { const у = document.querySelector(сел); return у ? у.textContent.replace(/\s+/g, ' ').trim() : ''; }, селектор);

/** Найти в JSON ответа сервера вид стола «Захвата» (у него есть поле захват.хозяева). */
function найтиВид(о, глубина) {
  глубина = глубина || 0;
  if (!о || typeof о !== 'object' || глубина > 4) return null;
  if (!Array.isArray(о) && о.захват && Array.isArray(о.захват.хозяева)) return о;
  for (const к of Object.keys(о)) { const р = найтиВид(о[к], глубина + 1); if (р) return р; }
  return null;
}

const сумма = ряд => ряд.reduce((а, б) => а + (Number(б) || 0), 0);

/** Одинаковы ли у двух игроков карта (хозяева, войска) и счёт (очки, области по номерам мест). */
function разницаВидов(а, б) {
  const x = а.захват, y = б.захват;
  const счёт = з => з.игроки.slice().sort((п, к) => п.номер - к.номер).map(и => и.номер + ':' + и.очков + '/' + и.областей).join(' ');
  const рез = [];
  if (x.раунд !== y.раунд) рез.push('раунд ' + x.раунд + ' против ' + y.раунд);
  if (JSON.stringify(x.хозяева) !== JSON.stringify(y.хозяева)) рез.push('хозяева областей разные');
  if (JSON.stringify(x.войска) !== JSON.stringify(y.войска)) рез.push('войска на карте разные');
  if (счёт(x) !== счёт(y)) рез.push('счёт разный: [' + счёт(x) + '] против [' + счёт(y) + ']');
  return рез;
}

