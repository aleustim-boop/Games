/* Партия кончилась: память посадки больше не держит человека за тем столом. */
async function партияКончилась() {
  console.log('10. Партия кончилась — новый поиск ставит в очередь, а не в старый стол');
  const МЕТКА_ТАНИ = 'tanya-vkladka-1';
  const таня = await встать(ТАНЯ, 'Таня', { метка: МЕТКА_ТАНИ });
  const уля = await встать(УЛЯ, 'Уля', { метка: 'ulya-vkladka-1' });
  проверить(таня.тело.статус === 'ждёт' && простоСвели(уля), 'Таня ждала, Уля встала и сведена с ней');
  const опросТани = await спросить('/подбор-новости', { ключОжидания: таня.тело.ключОжидания });
  проверить(простоСвели(опросТани) && опросТани.тело.код === уля.тело.код, 'Таня получила место за столом с Улей');
  await выйтиИзКомнаты(уля.тело.код, уля.тело.пропуск);
  const стол = await спросить('/состояние', { код: опросТани.тело.код, пропуск: опросТани.тело.пропуск });
  проверить(Boolean(стол.тело.состояние) && стол.тело.состояние.этап === 'конец',
    'Уля вышла — партия за столом Тани кончилась, Таня всё ещё за столом');

  /* Партия шла какое-то время: дольше, чем очередь держит неспрошенную
     запись (иначе её старое «свели» ещё живо), но меньше памяти посадки —
     иначе посадка забылась бы по сроку, а не потому, что партия кончилась. */
  const ОЧЕРЕДЬ_ПОМНИТ = числоИзИсходника(ИСХОДНИК_ПОДБОРА, 'СРОК_БЕЗ_ОПРОСА_МС', 'server/подбор.js');
  const ПОСАДКА_ПОМНИТ = числоИзИсходника(ИСХОДНИК_СЕРВЕРА, 'ПОМНИМ_ПОСАДКУ_ПОДБОРА_МС', 'server/сервер.js');
  проверить(ОЧЕРЕДЬ_ПОМНИТ + 2000 < ПОСАДКА_ПОМНИТ,
    'очередь забывает запись раньше, чем сервер забывает посадку (' + ОЧЕРЕДЬ_ПОМНИТ + ' < ' + ПОСАДКА_ПОМНИТ + ')');
  перевестиЧасы(Math.round((ОЧЕРЕДЬ_ПОМНИТ + ПОСАДКА_ПОМНИТ) / 2));

  const новыйПоиск = await встать(ТАНЯ, 'Таня', { метка: МЕТКА_ТАНИ });
  проверить(новыйПоиск.код === 200 && новыйПоиск.тело.статус === 'ждёт' && !новыйПоиск.тело.код,
    'новый поиск Тани поставил её в очередь, а не вернул за кончившийся стол');
  if (новыйПоиск.тело.ключОжидания) await спросить('/подбор-отмена', { ключОжидания: новыйПоиск.тело.ключОжидания });
}

/* Хвост 4: потолок комнат с ботом по кнопке на один номер. Часы переводим
   по минуте между нажатиями — так ведёт себя скрипт «комната в минуту». */
async function потолокКнопки() {
  const ПОТОЛОК = числоИзИсходника(ИСХОДНИК_СЕРВЕРА, 'БОТОВ_ПО_КНОПКЕ_ЗА_ОКНО', 'server/сервер.js');
  const ОКНО = числоИзИсходника(ИСХОДНИК_СЕРВЕРА, 'ОКНО_БОТОВ_ПО_КНОПКЕ_МС', 'server/сервер.js');
  const МИНУТА = 60 * 1000;
  console.log('11. Потолок кнопки: ' + ПОТОЛОК + ' комнат с ботом за ' + (ОКНО / МИНУТА) + ' мин, дальше 429');
  проверить(ПОТОЛОК === 6 && ОКНО === 10 * МИНУТА, 'потолок — 6 комнат с ботом за 10 минут, как решил штаб');
  const МЕТКА_ШУРЫ = 'shura-vkladka-1';

  let создано = 0;
  for (let шаг = 0; шаг < ПОТОЛОК; шаг++) {
    const шура = await встать(ШУРА, 'Шура', { метка: МЕТКА_ШУРЫ });
    const кнопка = await кнопкаБота(ШУРА, 'Шура', шура.тело.ключОжидания);
    if (простоСвели(кнопка)) {
      создано++;
      // Вышел из-за стола — следующий поиск снова ставит в очередь.
      await выйтиИзКомнаты(кнопка.тело.код, кнопка.тело.пропуск);
    }
    перевестиЧасы(МИНУТА);
  }
  проверить(создано === ПОТОЛОК, 'по минуте между нажатиями Шура получил ' + ПОТОЛОК + ' комнат с ботом (получил: ' + создано + ')');

  const седьмой = await встать(ШУРА, 'Шура', { метка: МЕТКА_ШУРЫ });
  проверить(седьмой.тело.статус === 'ждёт', 'Шура снова встал в очередь');
  const отказ = await кнопкаБота(ШУРА, 'Шура', седьмой.тело.ключОжидания);
  проверить(отказ.код === 429 && typeof отказ.тело.ошибка === 'string' && отказ.тело.ошибка.length > 5 &&
    !отказ.тело.код && !отказ.тело.пропуск,
    'седьмая комната за 10 минут — отказ 429 со словами, без кода и пропуска');
  const всёЕщё = await встать(ШУРА, 'Шура', { метка: МЕТКА_ШУРЫ });
  проверить(всёЕщё.тело.статус === 'ждёт' && всёЕщё.тело.ключОжидания === седьмой.тело.ключОжидания,
    'после отказа Шура остался в очереди под тем же ключом');
  // Иначе очередь свела бы Элю с ждущим Шурой, и кнопка Эли была бы ни при чём.
  await спросить('/подбор-отмена', { ключОжидания: седьмой.тело.ключОжидания });

  const эля = await встать(ЭЛЯ, 'Эля', { метка: 'elya-vkladka-1' });
  const кнопкаЭли = await кнопкаБота(ЭЛЯ, 'Эля', эля.тело.ключОжидания);
  проверить(простоСвели(кнопкаЭли), 'Эля в то же время получила комнату с ботом — потолок у каждого номера свой');

  // Первой комнате Шуры исполняется ровно окно (с запасом в секунду) — одна уходит из счёта.
  перевестиЧасы(ОКНО - ПОТОЛОК * МИНУТА + 1000);
  const послеОкна = await встать(ШУРА, 'Шура', { метка: МЕТКА_ШУРЫ });
  const кнопкаПослеОкна = await кнопкаБота(ШУРА, 'Шура', послеОкна.тело.ключОжидания);
  проверить(простоСвели(кнопкаПослеОкна), 'через 10 минут после первой комнаты кнопка Шуры снова работает');
}

