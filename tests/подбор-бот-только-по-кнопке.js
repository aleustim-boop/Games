/** Число из строки «const ИМЯ = 10 * 60 * 1000;». Не нашлось — проверка обрывается. */
function числоИзИсходника(текст, имя, откуда) {
  const найдено = текст.match(new RegExp('const ' + имя + ' = ([0-9 *]+);'));
  if (!найдено) throw new Error('в ' + откуда + ' не найдено число ' + имя);
  return найдено[1].split('*').reduce(function (итог, часть) { return итог * Number(часть.trim()); }, 1);
}

