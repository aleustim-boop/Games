  проверить(простоСвели(опросВаси) && опросВаси.тело.код === гоша.тело.код, 'опрос Васи забрал место в паре');
  await выйтиИзКомнаты(гоша.тело.код, гоша.тело.пропуск);
  await выйтиИзКомнаты(опросВаси.тело.код, опросВаси.тело.пропуск);
  const стол = await спросить('/состояние', { код: гоша.тело.код, пропуск: гоша.тело.пропуск });
  проверить(!стол.тело.состояние, 'оба вышли — комнаты пары больше нет');
  проверить((await сколькоКомнат()) === было, 'число комнат вернулось к прежнему');
