/** Копия server/сервер.js с порчей — во временной папке системы, не в проекте. */
function сделатьКопиюСПорчей(буква) {
  const порча = ПОРЧИ[буква];
  if (!порча) порчаНеПрименилась('нет порчи «' + буква + '», есть: ' + Object.keys(ПОРЧИ).join(', '));
  let текст = fs.readFileSync(ПУТЬ_СЕРВЕРА, 'utf8');
  // Файл может лежать с переводами строк Windows — замены пишем так же.
  const перевод = текст.indexOf('\r\n') !== -1 ? '\r\n' : '\n';
  for (const [было, стало] of порча.замены) {
    const искомое = было.split('\n').join(перевод);
    const сколько = текст.split(искомое).length - 1;
    if (сколько !== 1) {
      порчаНеПрименилась('строка найдена ' + сколько + ' раз, нужно ровно 1:\n' + было);
    }
    const замена = стало.split('\n').join(перевод);
    текст = текст.replace(искомое, function () { return замена; });
  }
  const путь = path.join(os.tmpdir(), 'подбор-бот-порча-' + буква + '-' + process.pid + '.js');
  fs.writeFileSync(путь, текст, 'utf8');
  return путь;
}

