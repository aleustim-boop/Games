#!/usr/bin/env node
'use strict';

/* =====================================================================
   СРОЧНАЯ ЗАПИСЬ РАЗДАЧИ ДНЯ: результат раздачи должен лечь на диск
   сразу после игры, а не через пять секунд.

   Та же беда, что чинилась в server/рейтинг.js и server/сила-игроков.js
   (см. tests/срочная-запись-рейтинга.js и tests/срочная-запись-силы.js),
   нашлась и в server/раздача-дня.js: результат менял память сразу, а на
   диск падал отложенно (ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ = 5000). Человек сыграл
   раздачу дня, увидел на экране «вы победили, место 4», сервер упал в
   ближайшие пять секунд — и после перезапуска его результата в сводке нет.

   ПОЧЕМУ ЗДЕСЬ НЕТ РАЗДЕЛЕНИЯ «ВАЖНОЕ / МЕЛОЧЬ», как в накопительном
   рейтинге. В рейтинге бывает партия с нулевой ценой (лёгкий бот,
   исчерпанный суточный потолок) — число на экране в этом случае и
   вправду не меняется, такую мелочь можно отложить. У раздачи дня
   единственное место, где вообще меняется память, — конец функции
   «записать», и оно срабатывает только когда результат принят
   по-настоящему (все проверки — подпись, день, исход, число ходов,
   «не сыграно дважды» — уже прошли); та же самая память сразу читается
   «сводкой» (сыграли, выиграли, моё место), которую человек видит на
   экране сразу после раздачи. Случая «результат принят, но видимо
   ничего не изменилось» здесь не бывает, поэтому исправление — «пишем
   всегда сразу», без деления, и вторая часть проверки (мелочь остаётся
   отложенной) здесь не нужна: отклонённый результат (второй раз за день,
   не из Telegram) вообще не доходит до записи и файла не создаёт —
   это проверяется отдельно, ниже.

   КАК ПРОВЕРЯЕМ «упало сразу после раздачи», не дожидаясь настоящего
   падения и не ожидая реальных пяти секунд: результат записывается в
   ОТДЕЛЬНОМ процессе node, который завершается через process.exit(0)
   сразу после записать() — без вызова дописать(). Если результат должен
   был лечь на диск немедленно (записатьСрочно) — writeFileSync успевает
   отработать ДО exit(0), и файл на диске есть с нужным результатом. Если
   код вернулся к старой отложенной записи — файла нет вовсе.

   ЧТО ПРОВЕРЯЕМ:
     1) принятый результат (человек из Telegram, день сегодняшний,
        исход и число ходов проходят все проверки) — после «падения»
        сразу после записи результат на диске ЕСТЬ;
     2) отклонённый результат (без подписи Telegram) — при том же самом
        «падении» на диске по-прежнему НИЧЕГО НЕТ: отказ не меняет память,
        значит и писать на диск нечего — это не мелочь, а отсутствие
        изменения вовсе.

   УМЕЕТ ЛИ ОНА КРАСНЕТЬ. node tests/срочная-запись-раздачи.js --сломать
   берёт временную копию server/раздача-дня.js и возвращает срочную
   запись результата обратно к пятисекундной отложенной (setTimeout вместо
   немедленной записатьСейчас внутри записатьСрочно) — ровно та поломка,
   от которой предостерегал штаб. На такой копии пункт (1) обязан
   провалиться: результата на диске сразу после «падения» уже не будет.

   Боевых данных не касается: копия server/ и папка данных — во временных
   каталогах (mkdtempSync), результат каждый раз записывается в отдельном
   дочернем процессе node, чтобы «падение сразу после exit» было
   настоящим, а не догадкой по логике кода.

   Запуск:
     node tests/срочная-запись-раздачи.js             (обычный прогон)
     node tests/срочная-запись-раздачи.js --сломать   (обязан провалиться)
   Выход 0 — провалов нет, 1 — провал (смотреть строки «ПРОВАЛ» в выводе).
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const СЛОМАТЬ = process.argv.includes('--сломать');

const ПРОВЕРКИ = [];
function проверить(имя, условие, подробности) {
  ПРОВЕРКИ.push({ имя: имя, ошибка: условие ? null : (подробности || 'условие не выполнено') });
}

/* Все временные папки этого прогона (копия server/ и по одной у каждого
   дочернего раннера) — чтобы убрать их за собой в самом конце, а не
   оставлять мусор во временной папке ОС на каждый запуск. */
const ВСЕ_ВРЕМЕННЫЕ_ПАПКИ = [];

/** Своя временная папка с заданным префиксом — и сразу на учёт для уборки. */
function новаяВременнаяПапка(префикс) {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), префикс));
  ВСЕ_ВРЕМЕННЫЕ_ПАПКИ.push(папка);
  return папка;
}

/* Убираем СВОИ временные папки по любому выходу процесса —
   process.on('exit') срабатывает и на process.exit(), и на непойманную
   ошибку. Раньше эти папки никогда не удалялись и копились на диске. */
process.on('exit', function () {
  for (const папка of ВСЕ_ВРЕМЕННЫЕ_ПАПКИ) {
    try { fs.rmSync(папка, { recursive: true, force: true, maxRetries: 3 }); } catch (е) { /* не страшно */ }
  }
});

/** Своя копия server/ во временной папке — боевой код и боевые данные не трогаем. */
function подготовитьКопиюСервера() {
  const врем = новаяВременнаяПапка('срочная-запись-раздачи-');
  fs.cpSync(path.join(КОРЕНЬ, 'server'), path.join(врем, 'server'), { recursive: true });
  return path.join(врем, 'server', 'раздача-дня.js');
}

/**
 * Порча копии: возвращает записатьСрочно() обратно к пятисекундной
 * отложенной записи — ровно та регрессия, от которой предостерегал штаб.
 */
function испортитьКопию(путьКРаздаче) {
  const исходник = fs.readFileSync(путьКРаздаче, 'utf8');
  const было = 'function записатьСрочно() {\n' +
    '  if (!записьРазрешена) return;\n' +
    '  естьЧтоЗаписать = true;\n' +
    '  записатьСейчас();\n' +
    '}';
  if (исходник.indexOf(было) === -1) {
    throw new Error('не нашёл тело записатьСрочно() для порчи — код server/раздача-дня.js изменился, поправьте tests/срочная-запись-раздачи.js');
  }
  const испорчено = исходник.replace(было,
    'function записатьСрочно() {\n' +
    '  if (!записьРазрешена) return;\n' +
    '  естьЧтоЗаписать = true;\n' +
    '  /* ИСПОРЧЕНО ПРОВЕРКОЙ tests/срочная-запись-раздачи.js --сломать: снова ждём 5 секунд */\n' +
    '  var т = setTimeout(function () { записатьСейчас(); }, 5000);\n' +
    '  if (т.unref) т.unref();\n' +
    '}');
  fs.writeFileSync(путьКРаздаче, испорчено, 'utf8');
}

/**
 * Раннер: в отдельном процессе записывает один результат и СРАЗУ
 * завершается через process.exit(0), без дописать() — модель «сервер
 * упал в первую же миллисекунду после раздачи дня».
 */
function кодРаннера(папкаДанных, путьКРаздаче, день, номер, исход, ходов) {
  return [
    "process.env.GAMES_DATA = " + JSON.stringify(папкаДанных) + ";",
    "const раздача = require(" + JSON.stringify(путьКРаздаче) + ");",
    "раздача.включитьЗапись();",
    "раздача.записать(" + JSON.stringify(день) + ", " + JSON.stringify(номер) + ", "
      + JSON.stringify(исход) + ", " + JSON.stringify(ходов) + ");",
    "process.exit(0);"
  ].join('\n');
}

/** Записать результат в отдельном процессе и вернуть, что осталось на диске. */
function записатьВОтдельномПроцессе(путьКРаздаче, день, номер, исход, ходов) {
  const врем = новаяВременнаяПапка('срочная-запись-раздачи-раннер-');
  const папкаДанных = path.join(врем, 'данные');
  const файлРаннера = path.join(врем, 'раннер.js');
  fs.writeFileSync(файлРаннера, кодРаннера(папкаДанных, путьКРаздаче, день, номер, исход, ходов), 'utf8');

  execFileSync(process.execPath, [файлРаннера], { stdio: 'pipe' });

  const файлРаздачи = path.join(папкаДанных, 'раздача-дня.json');
  if (!fs.existsSync(файлРаздачи)) return null;
  return JSON.parse(fs.readFileSync(файлРаздачи, 'utf8'));
}

/** Итог игрока за день в прочитанном файле раздачи (или null). */
function итогИгрока(данные, день, номер) {
  if (!данные || !Array.isArray(данные.дни)) return null;
  const запись = данные.дни.find(function (д) { return д.день === день; });
  if (!запись || !Array.isArray(запись.результаты)) return null;
  return запись.результаты.find(function (р) { return р.номер === номер; }) || null;
}

/* -----------------------------------------------------------------------
   main
   ----------------------------------------------------------------------- */

const путьКРаздаче = подготовитьКопиюСервера();
if (СЛОМАТЬ) испортитьКопию(путьКРаздаче);

// «Сегодня» берём тем же способом, что и сам файл, — своей копии формата
// ключа дня проверка не заводит.
const { ключДня } = require(путьКРаздаче);
const сегодня = ключДня();

/* Сценарий 1: результат принят — человек из Telegram, день сегодняшний,
   исход и число ходов честные. Это то, что человек видит на экране сразу
   после раздачи, — «важное», значит должно лечь на диск немедленно. */
const данные1 = записатьВОтдельномПроцессе(путьКРаздаче, сегодня, 3001, 'победа', 22);
const итог1 = итогИгрока(данные1, сегодня, 3001);

проверить(
  'принятый результат раздачи есть на диске сразу после «падения» процесса',
  !!итог1 && итог1.исход === 'победа' && итог1.ходов === 22,
  данные1 === null
    ? 'файл раздачи вообще не появился — результат потерялся, как и предупреждал штаб'
    : 'на диске результат игрока 3001: ' + JSON.stringify(итог1) + ' (ждали победу за 22 хода)'
);

/* Сценарий 2: результат без подписи Telegram отклоняется ДО того, как
   память вообще меняется, — писать на диск нечего, файла не будет
   ни при обычной, ни при отложенной схеме. Проверяем это только на
   НЕиспорченной копии: смысл сценария не в том, что он обязан
   провалиться при --сломать (там и без того всё уходит в setTimeout —
   сценарий 2 ничего нового не покажет), а в том, что отказ не создаёт
   файла в обычной работе. */
if (!СЛОМАТЬ) {
  const данные2 = записатьВОтдельномПроцессе(путьКРаздаче, сегодня, null, 'победа', 10);
  проверить(
    'результат без подписи Telegram не пишется на диск — память не менялась',
    данные2 === null,
    'файл раздачи появился, хотя результат не должен был приняться: ' + JSON.stringify(данные2)
  );
}

console.log('');
let провалов = 0;
for (const п of ПРОВЕРКИ) {
  if (п.ошибка) {
    провалов++;
    console.log('  ПРОВАЛ ' + п.имя + ': ' + п.ошибка);
  } else {
    console.log('  ок     ' + п.имя);
  }
}
console.log('');
console.log('Итого проверок: ' + ПРОВЕРКИ.length + ', провалов: ' + провалов);
process.exit(провалов > 0 ? 1 : 0);
