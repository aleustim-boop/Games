/* =====================================================================
   МЕРКА СТРОКИ РЕКОРДА: влезает ли число побед и не выезжает ли что-нибудь.

   ЭТО НЕ АВТОПРОГОН ДЛЯ NODE. Файл вставляется в консоль браузера, когда
   игра открыта (http://127.0.0.1:8123/index.html).

   ЗАЧЕМ. К уровню соперника добавился стол («сложный · вшестером» — 19 знаков
   вместо 7), и подпись стала отбирать место у главного — у числа побед.
   На узком телефоне человек читал «12 по…» вместо «12 побед подряд», то есть
   ровно то число, ради которого он таблицу и открыл. Строку переделали в две
   строчки; эта мерка проверяет, что число видно целиком на всех ширинах.

   Отдельно проверяется прихожая сетевой игры: она одолжила себе те же классы
   («таблица__строка», «таблица__очки» и соседние), а строки там короткие
   и должны остаться в ОДНУ линию. Если правило таблицы рекордов случайно
   расползётся на всю страницу, места за столом разъедутся на две строчки —
   и это тут будет видно.

   КАК ПОЛЬЗОВАТЬСЯ (игра открыта, вы в меню):
       await МеркаРекорда.подложить();   // кладёт в память 10 записей, в том
                                         // числе «12 побед подряд» и старые,
                                         // у которых стола нет вовсе
       МеркаРекорда.померить();          // числа по всем ширинам
       МеркаРекорда.вернуть();           // вернуть прежние рекорды на место

   ВАЖНО: «подложить» подменяет рекорды в памяти браузера. Прежние она
   запоминает и возвращает по «вернуть», но если вкладку закрыть между
   двумя вызовами — прежние рекорды пропадут. На своей настоящей игре
   лучше не запускать.
   ===================================================================== */

(function () {
  'use strict';

  const КЛЮЧ = 'подкидной-дурак:рекорды';
  const ШИРИНЫ = [280, 320, 360, 390, 430];

  /* Нарочно самые неудобные записи, какие вообще бывают:
     - «12 побед подряд» — длиннее всех числовых надписей (её дизайнер снять
       вживую не смог: такой записи в хранилище нет);
     - подписи со столом самой большой длины («сложный · вшестером»);
     - старые записи БЕЗ стола — у них подпись из одного слова, и лишней
       точки перед ней быть не должно. */
  const ЗАПИСИ = [
    { очки: 12, дата: '01.09.2026', сложность: 'сложный · вшестером' },
    { очки: 10, дата: '28.08.2026', сложность: 'обычный · вшестером' },
    { очки: 7,  дата: '15.08.2026', сложность: 'сложный' },
    { очки: 5,  дата: '14.08.2026', сложность: 'лёгкий · впятером' },
    { очки: 4,  дата: '13.08.2026', сложность: 'обычный' },
    { очки: 3,  дата: '12.08.2026', сложность: 'обычный · парами' },
    { очки: 3,  дата: '11.08.2026', сложность: 'лёгкий' },
    { очки: 2,  дата: '10.08.2026', сложность: 'сложный · вчетвером' },
    { очки: 2,  дата: '09.08.2026', сложность: 'лёгкий · втроём' },
    { очки: 1,  дата: '08.08.2026', сложность: 'обычный · вшестером' }
  ];

  let прежние = null;

  function эл(id) { return document.getElementById(id); }
  function виден(id) { const у = эл(id); return у && у.classList.contains('экран--виден'); }

  /** Открыть экран рекордов, откуда бы мы ни были. */
  function открытьРекорды() {
    if (виден('экран-рекордов')) return;
    if (!виден('экран-меню')) {
      const назад = [].slice.call(document.querySelectorAll('button'))
        .filter(function (к) { return (к.textContent || '').trim() === 'Назад'; })[0];
      if (назад) назад.click();
    }
    const кн = эл('кнопка-рекорды');
    if (кн) кн.click();
  }

  /** Померить одну ширину: что обрезано, что выехало, сколько строк видно. */
  function померитьШирину() {
    const т = эл('таблица-рекордов');
    if (!т) return { беда: 'таблицы рекордов нет на экране' };
    const строки = [].slice.call(т.querySelectorAll('.таблица__строка'));
    const короб = т.getBoundingClientRect();

    const обрезаны = [];
    строки.forEach(function (р, i) {
      const о = р.querySelector('.таблица__очки');
      const с = р.querySelector('.таблица__сложность');
      const д = р.querySelector('.таблица__дата');
      const беды = [];
      if (о && о.scrollWidth > о.clientWidth + 1) беды.push('число побед обрезано');
      if (с && с.scrollWidth > с.clientWidth + 1) беды.push('подпись стола обрезана');
      if (д && д.scrollWidth > д.clientWidth + 1) беды.push('дата обрезана');
      if (р.getBoundingClientRect().right > window.innerWidth + 1) беды.push('строка выехала за экран');
      if (беды.length) обрезаны.push({ строка: i + 1, что: (о ? о.textContent : ''), беды: беды });
    });

    const целиком = строки.filter(function (р) {
      const б = р.getBoundingClientRect();
      return б.top >= короб.top - 1 && б.bottom <= короб.bottom + 1;
    }).length;

    return {
      ширина: window.innerWidth,
      высотаСтроки: строки.length ? Math.round(строки[0].getBoundingClientRect().height) : 0,
      обрезано: обрезаны,
      видноСтрокЦеликом: целиком + ' из ' + строки.length,
      нуженПрокрут: т.scrollHeight > т.clientHeight + 1,
      горизонтальнаяПрокруткаСтраницы: document.documentElement.scrollWidth > window.innerWidth + 1
    };
  }

  /** Прихожая сетевой игры: строки мест обязаны остаться в одну линию. */
  function померитьПрихожую() {
    const строки = [].slice.call(document.querySelectorAll('#экран-комнаты .таблица__строка'));
    if (строки.length === 0) return 'прихожая не открыта — откройте «Играть с другом» → «Создать игру»';
    const вЛинию = строки.every(function (р) {
      const центры = [].slice.call(р.children)
        .filter(function (д) { return д.getBoundingClientRect().width > 0; })
        .map(function (д) {
          const к = д.getBoundingClientRect();
          return Math.round(к.top + к.height / 2);
        });
      return центры.length > 0 && новыйНабор(центры).length === 1;
    });
    const точки = строки.map(function (р) {
      const с = р.querySelector('.таблица__сложность');
      return с ? getComputedStyle(с, '::before').content : 'нет';
    });
    return {
      мест: строки.length,
      всеВОднуЛинию: вЛинию,
      высоты: строки.map(function (р) { return Math.round(р.getBoundingClientRect().height); }),
      лишняяТочкаПередПодписью: точки.filter(function (т) { return т !== 'none'; }).length
    };
  }

  /** Свой «уникальные значения» — чтобы файл читался и в старом браузере. */
  function новыйНабор(список) {
    const итог = [];
    список.forEach(function (з) { if (итог.indexOf(з) === -1) итог.push(з); });
    return итог;
  }

  window.МеркаРекорда = {
    подложить: async function () {
      прежние = localStorage.getItem(КЛЮЧ);
      localStorage.setItem(КЛЮЧ, JSON.stringify({ лучший: 12, таблица: ЗАПИСИ }));
      location.reload();
      return 'подложил 10 записей и перезагружаю страницу; после загрузки — МеркаРекорда.померить()';
    },
    вернуть: function () {
      if (прежние === null) return 'прежних рекордов не запомнено (страницу перезагружали?)';
      localStorage.setItem(КЛЮЧ, прежние);
      location.reload();
      return 'вернул прежние рекорды';
    },
    померить: async function () {
      открытьРекорды();
      /* Рекорды приезжают из памяти не мгновенно: сразу после нажатия таблица
         ещё пуста, и мерка честно показала бы «0 строк из 0». Поэтому ждём,
         пока строки появятся, — до полутора секунд. */
      for (let ждём = 0; ждём < 15; ждём++) {
        const т = эл('таблица-рекордов');
        if (т && т.querySelector('.таблица__строка')) break;
        await new Promise(function (готово) { setTimeout(готово, 100); });
      }
      /* Ширину окна из кода не поменять — это делает тот, кто гоняет браузер
         (browser_resize). Поэтому меряем ту ширину, что сейчас, и напоминаем
         список остальных. */
      const итог = померитьШирину();
      итог.осталосьПроверитьШирины = ШИРИНЫ.filter(function (ш) { return ш !== window.innerWidth; });
      return итог;
    },
    прихожая: померитьПрихожую
  };
  console.log('Мерка готова: await МеркаРекорда.подложить(), потом МеркаРекорда.померить()');
})();
