'use strict';

/* =====================================================================
   ЗАМЕР ПЕРЕСАДКОЙ — насколько сложный соперник сильнее обычного
   ЗА СТОЛОМ КОМПАНИЕЙ (втроём, вчетвером, вшестером).

   ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Мерка «замер-уровней.js» умеет считать только два
   стола: вдвоём и вчетвером парами. А разработчик отчитался и за компанию
   («трое +0.7 → +5.9, четверо +1.4 → +4.3, шестеро +0.9 → +2.3»), и
   проверить эти числа было нечем. Теперь есть чем.

   КАК МЕРЯЕМ. За столом на N мест один игрок — испытуемый, остальные —
   обычные боты. Одна и та же раздача играется N раз, и каждый раз
   испытуемый пересаживается на следующее место (отсюда и название):
   кресла в дураке неравноправны, и без пересадки половина разницы в цифрах
   была бы разницей кресел, а не разницей ботов.

   ЧТО ЗНАЧИТ ЧИСЛО. Считаем, как часто испытуемый остаётся дураком.
   Если все за столом играют одинаково, дураком каждый становится в свою
   честную долю случаев — одну N-ю от партий, где дурак вообще нашёлся.
   «Преимущество» — это на сколько испытуемый оказывается дураком РЕЖЕ
   честной доли, в очках из ста. Ноль — играет как все, десять — заметно
   сильнее остальных, минус — слабее.

   ЧЕСТНОСТЬ САМОЙ МЕРКИ проверяется тут же: контрольный прогон, где
   испытуемый — тоже обычный бот. Там преимущество обязано выйти ровно 0.00,
   иначе врёт мерка, а не бот. Такая проверка ловит и перекос кресел,
   и ошибку в подсчёте долей.

   Запуск:
     node tests/замер-пересадкой.js               1000 раздач на каждый стол
     node tests/замер-пересадкой.js 3000          подробнее и дольше
     node tests/замер-пересадкой.js 3000 777      другой набор раздач

   Код возврата: 0 — мерка отработала честно (это НЕ значит «с ботом всё
   хорошо», про бота читайте числа). 1 — сломалась сама мерка: партии
   не доигрались или контрольный прогон дал не ноль.
   ===================================================================== */

const путь = require('path');
const игра = require(путь.join(__dirname, '..', 'js', 'game.js'));
const генератор = require(путь.join(__dirname, 'общий-генератор.js'));

генератор.захватитьСлучайность();

const ПРЕДЕЛ_ХОДОВ = 1200;          // компанией партии длиннее, потолок с запасом
const СТОЛЫ = [3, 4, 6];            // сколько мест за столом проверяем
const РАЗДАЧ_ПО_УМОЛЧАНИЮ = 1000;

let смещение = 424242;              // свой набор раздач, не тот, что у мерки уровней

function зерноРаздачи(номер) {
  return (номер * 7919 + смещение) | 0;
}

/** Имена мест за столом: первое всегда «человек» — так их зовёт сама игра. */
function места(сколько) {
  const список = ['человек'];
  for (let i = 1; i < сколько; i++) список.push(i === 1 ? 'бот' : 'бот-' + (i + 1));
  return список;
}

/** Слепок стола: по нему видно, сдвинулась ли партия хоть на шаг. */
function слепок(п) {
  const вРуках = п.игроки.map(function (и) { return (п.руки[и] || []).length; }).join('/');
  const отбитых = п.стол.filter(function (пара) { return пара.защита; }).length;
  return [игра.фаза(п), п.стол.length, отбитых, п.отбой.length, п.колода.length,
          вРуках, п.атакует, (п.пасы || []).join(',')].join('|');
}

/**
 * Сыграть одну партию. «уровниПоМестам» — на каждое место свой уровень бота.
 * Возвращает { дурак, беда }: дурак — имя места или null при ничьей.
 */
function сыгратьПартию(зерно, сколькоМест, уровниПоМестам) {
  генератор.поставитьЗерно(зерно);
  const п = игра.создатьПартию({
    сложность: 'обычный',           // уровень партии не важен: он задан по местам
    игроков: сколькоМест
  });
  let шагов = 0;
  while (!п.завершена && шагов++ < ПРЕДЕЛ_ХОДОВ) {
    const место = игра.ктоХодит(п);
    if (место === null) return { дурак: null, беда: 'партия не окончена, а ходить некому' };
    const было = слепок(п);
    игра.ходБота(п, место, уровниПоМестам[место]);
    if (слепок(п) === было) return { дурак: null, беда: 'ход «' + место + '» ничего не изменил' };
  }
  if (!п.завершена) return { дурак: null, беда: 'не кончилась за ' + ПРЕДЕЛ_ХОДОВ + ' ходов' };
  const проигравшие = п.проигравшие || [];
  return { дурак: проигравшие.length > 0 ? проигравшие[0] : null, беда: null };
}

/**
 * Прогон одного стола: испытуемый уровня «кто» против обычных ботов.
 * Каждая раздача играется столько раз, сколько мест за столом, —
 * испытуемый обходит все кресла.
 */
function прогон(сколькоМест, кто, раздач) {
  const имена = места(сколькоМест);
  let партий = 0;
  let дуракНашёлся = 0;            // партий, где дурак вообще был (не ничья)
  let былДураком = 0;              // из них — сколько раз дураком стал испытуемый
  const беды = [];

  for (let номер = 1; номер <= раздач; номер++) {
    const зерно = зерноРаздачи(номер);
    for (let кресло = 0; кресло < сколькоМест; кресло++) {
      const уровни = {};
      имена.forEach(function (имя, i) { уровни[имя] = (i === кресло) ? кто : 'обычный'; });
      const итог = сыгратьПартию(зерно, сколькоМест, уровни);
      if (итог.беда) {
        if (беды.length < 5) беды.push('раздача ' + номер + ', кресло ' + кресло + ': ' + итог.беда);
        continue;
      }
      партий++;
      if (итог.дурак !== null) {
        дуракНашёлся++;
        if (итог.дурак === имена[кресло]) былДураком++;
      }
    }
  }

  /* Честная доля: если все играют одинаково, дураком становишься в одной
     N-й части партий, где дурак вообще нашёлся. */
  const честнаяДоля = дуракНашёлся / сколькоМест;
  const преимущество = дуракНашёлся === 0
    ? 0
    : 100 * (честнаяДоля - былДураком) / дуракНашёлся;
  return {
    партий: партий,
    ничьих: партий - дуракНашёлся,
    дуракомБыл: дуракНашёлся === 0 ? 0 : 100 * былДураком / дуракНашёлся,
    честнаяДоля: 100 / сколькоМест,
    преимущество: преимущество,
    беды: беды
  };
}

function число(н) { return (Math.round(н * 10) / 10).toFixed(1); }

/* ---------------------------------------------------------------------
   ЗАПУСК
   --------------------------------------------------------------------- */

const доводы = process.argv.slice(2);
const РАЗДАЧ = доводы[0] === undefined ? РАЗДАЧ_ПО_УМОЛЧАНИЮ : Math.floor(Number(доводы[0]));
if (!Number.isFinite(РАЗДАЧ) || РАЗДАЧ < 1) {
  console.log('Число раздач должно быть целым и больше нуля, а сказано «' + доводы[0] + '».');
  process.exit(2);
}
if (доводы[1] !== undefined && Number.isFinite(Number(доводы[1]))) {
  смещение = Math.floor(Number(доводы[1])) | 0;
}

console.log('=== Замер пересадкой: сложный бот за столом компанией ===');
console.log('раздач на стол: ' + РАЗДАЧ + '; каждая играется столько раз, сколько мест,');
console.log('испытуемый обходит все кресла. Набор раздач (смещение зерна): ' + смещение + '\n');
console.log('«Преимущество» — насколько реже испытуемый остаётся дураком, чем');
console.log('положено по честной доле. 0 — играет как все, больше — сильнее.\n');

let бедВсего = 0;
let контрольВрёт = false;

for (const мест of СТОЛЫ) {
  const подписьСтола = { 3: 'втроём', 4: 'вчетвером', 6: 'вшестером' }[мест];
  console.log('--- ' + подписьСтола + ' (' + мест + ' места) ---');

  const контроль = прогон(мест, 'обычный', РАЗДАЧ);
  бедВсего += контроль.беды.length;
  console.log('  проверка мерки (испытуемый — тоже обычный): преимущество ' +
    число(контроль.преимущество) + ' — обязано быть 0.0');
  if (Math.abs(контроль.преимущество) > 0.05) {
    контрольВрёт = true;
    console.log('  !!! МЕРКА ВРЁТ: одинаковые боты дали не ноль, числам ниже верить нельзя');
  }

  const сложный = прогон(мест, 'сложный', РАЗДАЧ);
  бедВсего += сложный.беды.length;
  /* Знак пишем сами: у «минус ноль целых семи» плюс впереди выглядел бы
     как «+-0.7» — так уже вышло в первом прогоне, и это сбивает с толку. */
  const знак = сложный.преимущество >= 0 ? '+' : '';
  console.log('  сложный: дураком остаётся в ' + число(сложный.дуракомБыл) +
    '% партий (честная доля ' + число(сложный.честнаяДоля) + '%) → преимущество ' +
    знак + число(сложный.преимущество));
  console.log('  партий сыграно: ' + сложный.партий + ', из них ничьих: ' + сложный.ничьих);
  for (const б of сложный.беды.concat(контроль.беды)) console.log('  !!! ' + б);
  console.log('');
}

console.log('Недоигранных партий за весь замер: ' + бедВсего);
process.exit(бедВсего === 0 && !контрольВрёт ? 0 : 1);
