'use strict';

/* =====================================================================
   СТОРОЖ: РЕЙТИНГ-ЭКРАН ХОДИТ НА СЕРВЕР ТОЛЬКО ЧЕРЕЗ window.Сеть

   Договор проекта (CLAUDE.md): js/сеть.js — единственное место браузера,
   знающее сервер, коды и пропуска. У js/рейтинг-экран.js есть один
   законный fetch — функция «спроситьТаблицуБезСети», запасной путь для
   страниц БЕЗ js/сеть.js (шахматы.html, узкие node-проверки без окружения
   браузера). Вне этой функции fetch быть не должно вовсе: это и значило
   бы, что экран обошёл Сеть и стучится на сервер сам.

   Что проверяем:
     1. Функция «спроситьТаблицуБезСети» вообще нашлась в файле (иначе
        приём переименовали и весь сторож ослеп — тоже провал).
     2. Каждое вхождение fetch(...) в файле лежит внутри границ этой
        функции (границы — по балансу фигурных скобок, а не по номеру
        строки — переносы строк файла не важны).
     3. Экран хотя бы раз зовёт window.Сеть.рейтингТаблица — ноль найденного
        не пропуск, а провал: значит и обычный путь через Сеть исчез.
     4. Дверь «рейтингТаблица» объявлена в window.Сеть (js/сеть.js) —
        иначе экран зовёт то, чего в двери нет.

   Запуск:
     node tests/рейтинг-экран-без-своей-сети.js                — проект как есть
     node tests/рейтинг-экран-без-своей-сети.js <экран> <сеть> — свои копии
     node tests/рейтинг-экран-без-своей-сети.js --сломать [папка] — ломающий
         запуск: копия экрана (в указанной папке или во временной, если
         папка не дана) получает fetch ПОВЕРХ обычного маршрута, в обход
         window.Сеть.рейтингТаблица, — сторож обязан покраснеть. Файл
         проекта не трогается.
   ===================================================================== */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const ПУТЬ_ЭКРАНА = path.join(КОРЕНЬ, 'js', 'рейтинг-экран.js');
const ПУТЬ_СЕТИ = path.join(КОРЕНЬ, 'js', 'сеть.js');
const ИМЯ_ЗАПАСНОГО_ПУТИ = 'спроситьТаблицуБезСети';

/** Границы функции по имени: { начало, конец } — индексы в тексте файла,
 * конец найден по балансу фигурных скобок. null — функция не нашлась. */
function границыФункции(текст, имя) {
  const начало = текст.indexOf('function ' + имя + '(');
  if (начало === -1) return null;
  const индексСкобки = текст.indexOf('{', начало);
  if (индексСкобки === -1) return null;
  let глубина = 0;
  for (let i = индексСкобки; i < текст.length; i++) {
    if (текст[i] === '{') глубина++;
    else if (текст[i] === '}') {
      глубина--;
      if (глубина === 0) return { начало: начало, конец: i + 1 };
    }
  }
  return null;
}

function номерСтроки(текст, позиция) {
  return текст.slice(0, позиция).split('\n').length;
}

/** Список проверок { имя, годно } для пары файлов. */
function собратьПроверки(путьЭкрана, путьСети) {
  const проверки = [];
  function проверить(имя, годно) { проверки.push({ имя: имя, годно: Boolean(годно) }); }

  const текст = fs.readFileSync(путьЭкрана, 'utf8');
  const текстСети = fs.readFileSync(путьСети, 'utf8');

  const запаснойПуть = границыФункции(текст, ИМЯ_ЗАПАСНОГО_ПУТИ);
  проверить('нашлась функция запасного пути «' + ИМЯ_ЗАПАСНОГО_ПУТИ + '» (иначе приём устарел, сторож ослеп)',
    Boolean(запаснойПуть));

  const местаFetch = [];
  const образецFetch = /\bfetch\s*\(/g;
  let найдено;
  while ((найдено = образецFetch.exec(текст)) !== null) местаFetch.push(найдено.index);

  const заПределами = местаFetch.filter(function (позиция) {
    return !запаснойПуть || позиция < запаснойПуть.начало || позиция >= запаснойПуть.конец;
  });
  проверить('fetch(...) встречается в файле только внутри запасного пути' +
    (заПределами.length
      ? ' — нашёлся вне его на строке ' + заПределами.map(function (п) { return номерСтроки(текст, п); }).join(', ')
      : ' (вхождений всего: ' + местаFetch.length + ')'),
    заПределами.length === 0);

  const вызововСети = (текст.match(/Сеть\.рейтингТаблица\s*\(/g) || []).length;
  проверить('экран хотя бы раз зовёт window.Сеть.рейтингТаблица (найдено вызовов: ' + вызововСети + ')',
    вызововСети > 0);

  /* Без \b на конце: «рейтингТаблица» — кириллица, а \b в JS её не знает
     (\w — только латиница), граница слева/справа от неё может не сработать. */
  const дверьЕсть = /рейтингТаблица\s*:\s*(function|рейтингТаблица)/.test(текстСети);
  проверить('дверь «рейтингТаблица» объявлена в window.Сеть (' + путьСети + ')', дверьЕсть);

  return проверки;
}

function обычныйЗапуск(путьЭкрана, путьСети) {
  console.log('Экран: ' + путьЭкрана);
  console.log('Сеть:  ' + путьСети);
  const проверки = собратьПроверки(путьЭкрана, путьСети);
  проверки.forEach(function (п) { console.log((п.годно ? '  ok    ' : '  ПРОВАЛ ') + п.имя); });
  const провалов = проверки.filter(function (п) { return !п.годно; }).length;
  console.log('Итого проверок: ' + проверки.length + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
}

/** Ломающий запуск: копия экрана с fetch МИМО window.Сеть.рейтингТаблица. */
function ломающийЗапуск(доводПапка) {
  const папка = доводПапка ? path.resolve(доводПапка) : fs.mkdtempSync(path.join(os.tmpdir(), 'сторож-рейтинга-'));
  fs.mkdirSync(папка, { recursive: true });
  const копияЭкрана = path.join(папка, 'рейтинг-экран.js');
  const исходный = fs.readFileSync(ПУТЬ_ЭКРАНА, 'utf8');
  /* Порча: экран заводит свой fetch прямо на /рейтинг ВНЕ функции запасного
     пути — та самая беда, ради которой этот сторож и написан. Файл проекта
     не трогаем, портим только эту копию во временной/указанной папке. */
  fs.writeFileSync(копияЭкрана,
    исходный + '\nfetch("/рейтинг", { method: "POST" }); // порча --сломать: fetch мимо window.Сеть\n');
  console.log('[--сломать] копия испорченного экрана: ' + копияЭкрана);
  const прогон = spawnSync(process.execPath, [__filename, копияЭкрана, ПУТЬ_СЕТИ], { encoding: 'utf8' });
  console.log(прогон.stdout);
  if (прогон.status === 0) {
    console.log('ПРОВАЛ ломающего запуска: копия с fetch мимо Сети прошла проверку — сторож не краснеет');
    process.exit(1);
  }
  console.log('ок: копия с fetch в обход Сети покраснела, как и должна');
}

const доводы = process.argv.slice(2);
if (доводы[0] === '--сломать') {
  ломающийЗапуск(доводы[1]);
} else {
  обычныйЗапуск(
    доводы[0] ? path.resolve(доводы[0]) : ПУТЬ_ЭКРАНА,
    доводы[1] ? path.resolve(доводы[1]) : ПУТЬ_СЕТИ
  );
}
