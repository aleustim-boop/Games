/* =====================================================================
   ДВЕРЬ ПРОФИЛЯ ДУРАКА (Э7а плана «профиль по макету»).

   На index.html вкладка «Профиль» лобби (карточка «лобби-профиль» и
   полоса «лобби-вкладка-профиль», запасной вход без js/дурак-путь.js —
   тем же приёмом пользуется и сам путь через свой конфиг «открытьПрофиль»)
   раньше открывала старый экран «Как я играю» напрямую. Теперь при живом
   window.ЭкранПрофиля (js/профиль-экран.js) она ведёт в новый общий
   экран профиля, а без него — как раньше, чтобы старая страница из
   памяти телефона (без нового файла) не осталась с мёртвой кнопкой.

   ЧТО ПРОВЕРЯЕТ ЭТОТ ФАЙЛ. Поднимает НАСТОЯЩИЙ js/game.js в песочнице vm
   с поддельным DOM — приём взят из tests/карта-входов-в-рейтинг.js
   («поднятьGameJs»), но здесь classList настоящий (Set), а не пустышка:
   document.querySelectorAll('.экран') должен и вправду находить узлы —
   без этого нельзя честно проверить «запомнитьГдеБыли»/«показатьЭкран»,
   на которых и держится дверь профиля.

     а) с window.ЭкранПрофиля — клик «лобби-вкладка-профиль» зовёт
        ЭкранПрофиля.открыть('дурак') и НЕ трогает старый счёт (окно
        «Рейтинг».прочитать ни разу не позвано, «экран-рейтинга» не
        показан).
     б) без window.ЭкранПрофиля — прежнее поведение: клик открывает
        «Как я играю» напрямую (window.Рейтинг.прочитать('дурак') позван,
        «экран-рейтинга» показан).
     в) возврат «Назад» из «Как я играю», открытого поверх профиля,
        ведёт обратно в профиль, а не в лобби: «экран-профиля-игрока»
        видим ДО, «экран-рейтинга» — после открытия счёта, и снова
        «экран-профиля-игрока» — после «Назад» (то есть после настоящих
        показатьЭкран/запомнитьГдеБыли/вернутьсяОткудаПришли game.js).
     г) правка ревьюера: «служебныйЭкранОткрыт» видит профиль в числе
        ЭКРАНЫ_ПОВЕРХ — опрос сети не должен выдёргивать из профиля,
        открытого поверх комнаты ожидания (тот же приём, что у правил
        и рекордов).

   Запуск:
       node tests/дверь-профиля-дурака.js             — чистый прогон
       node tests/дверь-профиля-дурака.js --сломать   — ломающий прогон:
         портит ТРИ КОПИИ js/game.js по очереди (настоящий файл не трогает
         ни на секунду; путь к каждой копии печатается) — по одной на
         пункты а), в) и г) — и требует, чтобы соответствующая проверка
         покраснела. Не покраснела — тест сам себя объявляет слепым.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const os = require('os');

const КОРЕНЬ = path.join(__dirname, '..');
const ПУТЬ_GAME_JS_ОРИГИНАЛ = path.join(КОРЕНЬ, 'js', 'game.js');

const сломать = process.argv.indexOf('--сломать') !== -1;

/* Экраны, которым в настоящей разметке дан class="экран" и которые нужны
   этому файлу: лобби (стартовое место), профиль, счёт и итог (его
   «запомнитьГдеБыли» смотрит первым). Дальше по коду встречаются и другие
   id с префиксом «экран-», но для этой проверки они не нужны — заводить
   лишние узлы означало бы тащить в песочницу разметку, которую эта дверь
   не трогает. */
const ЭКРАНЫ_ДЛЯ_ПЕСОЧНИЦЫ = ['экран-лобби', 'экран-профиля-игрока', 'экран-рейтинга', 'экран-результата'];

/* ---------------------------------------------------------------------
   Поддельный звук — тот же приём, что в tests/карта-входов-в-рейтинг.js:
   window.AudioContext нужен, только чтобы game.js не упал на щелчке.
   --------------------------------------------------------------------- */
function поддельныйЗвук() {
  return {
    state: 'running', currentTime: 0, resume() {},
    createOscillator() {
      return { connect() {}, start() {}, stop() {}, type: '', frequency: { setValueAtTime() {} } };
    },
    createGain() {
      return { connect() {}, gain: { setValueAtTime() {}, exponentialRampToValueAtTime() {} } };
    },
    destination: {}
  };
}

/**
 * Поднять js/game.js в песочнице vm с поддельным DOM, где classList —
 * НАСТОЯЩИЙ (через Set), а document.querySelectorAll('.экран') находит
 * узлы из ЭКРАНЫ_ДЛЯ_ПЕСОЧНИЦЫ (заведены заранее, ДО запуска game.js —
 * в настоящем браузере разметка тоже стоит в DOM ещё до первого JS).
 * Остальные id — как в карта-входов-в-рейтинг.js: пустышка «по требованию»,
 * classList у неё тоже настоящий (безопасный лишний функционал, не мешает).
 *
 * опции.сЭкраномПрофиля — подложить window.ЭкранПрофиля.открыть(игра),
 *   который только запоминает вызов (журналПрофиля), экран не трогает —
 *   так и должно быть: реальный показ владеет им сам, не наша забота.
 * опции.сРейтингом — подложить window.Рейтинг.{прочитать,записатьПартию}:
 *   «прочитать» запоминает вызов (журналРейтинг) и отдаёт пустую сводку
 *   (нет партий — «показатьПустойСчёт», безопасная ветка). По умолчанию true.
 *
 * Возвращает песочницу целиком (в ней доступны и window/document, и —
 * как top-level функции game.js — показатьЭкран/запомнитьГдеБыли/
 * вернутьсяОткудаПришли/служебныйЭкранОткрыт напрямую: в vm-контексте
 * function-декларации верхнего уровня становятся его собственными
 * свойствами, тем же приёмом, каким браузер вешает их на window).
 */
function поднятьGameJs(путь, опции) {
  опции = опции || {};
  const исходник = fs.readFileSync(путь, 'utf8');

  const журналПрофиля = [];
  const журналРейтинг = [];

  const узлыПоId = new Map();
  const НЕ_СОЗДАВАТЬ_САМИ = new Set(['кнопка-рейтинг-игроков']);

  function привязать(узел) {
    узел.parentNode = корень;
    if (узел.id) узлыПоId.set(узел.id, узел);
  }

  const корень = {
    insertBefore(новый) { привязать(новый); return новый; },
    appendChild(новый) { привязать(новый); return новый; }
  };

  function новыйУзел() {
    const классы = new Set();
    const слушатели = {};
    return {
      id: '',
      children: [],   // пусто: в этой проверке никто не строит внутрь этих узлов кнопки-ряды
      classList: {
        add(к) { классы.add(к); },
        remove(к) { классы.delete(к); },
        toggle(к, состояние) {
          const надо = состояние === undefined ? !классы.has(к) : Boolean(состояние);
          if (надо) классы.add(к); else классы.delete(к);
          return надо;
        },
        contains(к) { return классы.has(к); }
      },
      style: { setProperty() {}, removeProperty() {} },
      dataset: {}, textContent: '', innerHTML: '', value: '', disabled: false,
      setAttribute() {}, getAttribute() { return null; }, removeAttribute() {}, hasAttribute() { return false; },
      appendChild(р) { привязать(р); return р; },
      removeChild() {},
      insertBefore(р) { привязать(р); return р; },
      remove() {},
      focus() {}, blur() {},
      addEventListener(тип, ф) { (слушатели[тип] = слушатели[тип] || []).push(ф); },
      removeEventListener(тип, ф) {
        if (!слушатели[тип]) return;
        const где = слушатели[тип].indexOf(ф);
        if (где !== -1) слушатели[тип].splice(где, 1);
      },
      click() { (слушатели.click || []).slice().forEach(ф => ф()); },
      querySelector() { return null; }, querySelectorAll() { return []; },
      closest() { return null; }, contains() { return false; },
      nextSibling: null, parentNode: корень,
      getBoundingClientRect() { return { width: 360, height: 40, top: 0, left: 0, right: 360, bottom: 40 }; }
    };
  }

  function получитьУзел(id) {
    if (узлыПоId.has(id)) return узлыПоId.get(id);
    if (НЕ_СОЗДАВАТЬ_САМИ.has(id)) return null;
    const узел = новыйУзел();
    узел.id = id;
    узел.parentNode = корень;
    узлыПоId.set(id, узел);
    return узел;
  }

  // Экраны заводим ЗАРАНЕЕ, с class="экран" — как в настоящей разметке,
  // до первой строчки game.js, которая ещё ничего не спросила.
  ЭКРАНЫ_ДЛЯ_ПЕСОЧНИЦЫ.forEach(id => получитьУзел(id).classList.add('экран'));

  const документ = {
    getElementById: получитьУзел,
    createElement: новыйУзел,
    createTextNode: новыйУзел,
    querySelector() { return null; },
    querySelectorAll(селектор) {
      if (селектор === '.экран') {
        return Array.from(узлыПоId.values()).filter(у => у.classList.contains('экран'));
      }
      return [];
    },
    addEventListener() {}, removeEventListener() {},
    documentElement: новыйУзел(), body: новыйУзел(), head: новыйУзел(),
    readyState: 'complete'
  };

  const окно = {
    addEventListener() {}, removeEventListener() {},
    matchMedia() { return { matches: false, addEventListener() {}, addListener() {} }; },
    localStorage: { getItem() { return null; }, setItem() {}, removeItem() {} },
    innerWidth: 390, innerHeight: 844,
    requestAnimationFrame(ф) { return setTimeout(ф, 0); },
    getComputedStyle() { return { fontSize: '16px', lineHeight: '19.2px', getPropertyValue() { return ''; } }; },
    AudioContext: поддельныйЗвук
  };
  окно.document = документ;

  if (опции.сЭкраномПрофиля) {
    окно.ЭкранПрофиля = { открыть(игра) { журналПрофиля.push(игра); } };
  }
  if (опции.сРейтингом !== false) {
    окно.Рейтинг = {
      прочитать(игра) { журналРейтинг.push(игра); return Promise.resolve({}); },
      записатьПартию() {}
    };
  }

  const песочница = {
    window: окно, document: документ,
    setTimeout, clearTimeout, setInterval, clearInterval,
    Math, Date, JSON, Number, String, Array, Object, Boolean, RegExp, Error, isFinite,
    console: { log() {}, warn() {}, error() {} },
    requestAnimationFrame: окно.requestAnimationFrame,
    getComputedStyle: окно.getComputedStyle,
    AudioContext: поддельныйЗвук
  };
  песочница.globalThis = песочница;
  vm.createContext(песочница);
  vm.runInContext(исходник, песочница, { filename: 'js/game.js (дверь профиля дурака)' });

  return {
    сцена: песочница,
    получитьУзел: получитьУзел,
    журналПрофиля: журналПрофиля,
    журналРейтинг: журналРейтинг
  };
}

/* =======================================================================
   ВЕСЬ НАБОР ПРОВЕРОК ОДНИМ ПРОГОНОМ. Чистый запуск зовёт её с настоящим
   файлом, ломающий — по очереди с тремя испорченными копиями.
   ======================================================================= */
function прогнать(путьGameJs) {
  const строки = [];
  let провалов = 0;

  function проверить(имя, условие, подробности) {
    if (условие) {
      строки.push('OK    ' + имя);
    } else {
      провалов++;
      строки.push('ПЛОХО ' + имя + (подробности ? ' — ' + подробности : ''));
    }
  }

  /* --- а) с window.ЭкранПрофиля: дверь ведёт в новый экран, старый счёт не трогает --- */
  let игрокА = null;
  try {
    игрокА = поднятьGameJs(путьGameJs, { сЭкраномПрофиля: true });
    проверить('а) js/game.js поднимается в песочнице (с window.ЭкранПрофиля)', true);
  } catch (сбой) {
    проверить('а) js/game.js поднимается в песочнице (с window.ЭкранПрофиля)', false, сбой.message);
  }
  if (игрокА) {
    const узел = игрокА.получитьУзел('лобби-вкладка-профиль');
    проверить('а) узел «лобби-вкладка-профиль» найден', Boolean(узел));
    if (узел) {
      узел.click();
      проверить('а) клик зовёт window.ЭкранПрофиля.открыть ровно один раз',
        игрокА.журналПрофиля.length === 1, 'журналПрофиля: ' + JSON.stringify(игрокА.журналПрофиля));
      проверить('а) открывает профиль «дурак»',
        игрокА.журналПрофиля[0] === 'дурак', 'получено: ' + JSON.stringify(игрокА.журналПрофиля));
      проверить('а) старый счёт НЕ тронут — window.Рейтинг.прочитать ни разу не позван',
        игрокА.журналРейтинг.length === 0, 'журналРейтинг: ' + JSON.stringify(игрокА.журналРейтинг));
      const экранСчёта = игрокА.получитьУзел('экран-рейтинга');
      проверить('а) «экран-рейтинга» (старое «Как я играю») не показан',
        !экранСчёта.classList.contains('экран--виден'));
    }
  }

  /* --- б) без window.ЭкранПрофиля: прежнее поведение не сломано --- */
  let игрокБ = null;
  try {
    игрокБ = поднятьGameJs(путьGameJs, { сЭкраномПрофиля: false });
    проверить('б) js/game.js поднимается в песочнице (без window.ЭкранПрофиля)', true);
  } catch (сбой) {
    проверить('б) js/game.js поднимается в песочнице (без window.ЭкранПрофиля)', false, сбой.message);
  }
  if (игрокБ) {
    const узел = игрокБ.получитьУзел('лобби-вкладка-профиль');
    проверить('б) узел «лобби-вкладка-профиль» найден', Boolean(узел));
    if (узел) {
      узел.click();
      проверить('б) window.Рейтинг.прочитать позван один раз — открылось «Как я играю»',
        игрокБ.журналРейтинг.length === 1, 'журналРейтинг: ' + JSON.stringify(игрокБ.журналРейтинг));
      проверить('б) счёт запрошен про «дурак»',
        игрокБ.журналРейтинг[0] === 'дурак', 'получено: ' + JSON.stringify(игрокБ.журналРейтинг));
      const экранСчёта = игрокБ.получитьУзел('экран-рейтинга');
      проверить('б) «экран-рейтинга» показан (прежнее поведение)',
        экранСчёта.classList.contains('экран--виден'));
    }
  }

  /* --- в) возврат «Назад» из «Как я играю» после профиля --- */
  let игрокВ = null;
  try {
    игрокВ = поднятьGameJs(путьGameJs, { сЭкраномПрофиля: true });
    проверить('в) js/game.js поднимается в песочнице (для проверки возврата)', true);
  } catch (сбой) {
    проверить('в) js/game.js поднимается в песочнице (для проверки возврата)', false, сбой.message);
  }
  if (игрокВ) {
    // Профиль открыт — тем же приёмом, каким js/профиль-экран.js показывает
    // себя через мост window.ИграПоСети.экран → показатьЭкран game.js.
    игрокВ.сцена.показатьЭкран('экран-профиля-игрока');
    проверить('в) профиль виден после открытия',
      игрокВ.получитьУзел('экран-профиля-игрока').classList.contains('экран--виден'));

    const кнопкаМойСчёт = игрокВ.получитьУзел('кнопка-мой-счёт');
    проверить('в) узел «кнопка-мой-счёт» найден', Boolean(кнопкаМойСчёт));
    if (кнопкаМойСчёт) {
      кнопкаМойСчёт.click();   // «Как я играю» из профиля (та же кнопка, что жмёт открытьСчёт рейтинг-экрана)
      проверить('в) «Как я играю» показан после клика',
        игрокВ.получитьУзел('экран-рейтинга').classList.contains('экран--виден'));
      проверить('в) профиль спрятан, пока открыто «Как я играю»',
        !игрокВ.получитьУзел('экран-профиля-игрока').classList.contains('экран--виден'));

      const кнопкаНазад = игрокВ.получитьУзел('кнопка-рейтинг-назад');
      проверить('в) узел «кнопка-рейтинг-назад» найден', Boolean(кнопкаНазад));
      if (кнопкаНазад) {
        кнопкаНазад.click();
        проверить('в) «Назад» вернул в профиль, а не в лобби',
          игрокВ.получитьУзел('экран-профиля-игрока').classList.contains('экран--виден'),
          '«экран-лобби» видим: ' + игрокВ.получитьУзел('экран-лобби').classList.contains('экран--виден'));
        проверить('в) «экран-рейтинга» после возврата скрыт',
          !игрокВ.получитьУзел('экран-рейтинга').classList.contains('экран--виден'));
      }
    }
  }

  /* --- г) правка ревьюера: профиль в числе ЭКРАНЫ_ПОВЕРХ --- */
  let игрокГ = null;
  try {
    игрокГ = поднятьGameJs(путьGameJs, { сЭкраномПрофиля: true });
    проверить('г) js/game.js поднимается в песочнице (для проверки ЭКРАНЫ_ПОВЕРХ)', true);
  } catch (сбой) {
    проверить('г) js/game.js поднимается в песочнице (для проверки ЭКРАНЫ_ПОВЕРХ)', false, сбой.message);
  }
  if (игрокГ) {
    игрокГ.сцена.показатьЭкран('экран-профиля-игрока');
    проверить('г) «служебныйЭкранОткрыт» видит открытый профиль (ЭКРАНЫ_ПОВЕРХ) — ' +
      'опрос сети не выдернет игрока из профиля поверх комнаты ожидания',
      игрокГ.сцена.служебныйЭкранОткрыт() === true);
  }

  return { строки: строки, провалов: провалов };
}

/* =======================================================================
   ЗАПУСК
   ======================================================================= */

if (!сломать) {
  console.log('=== Дверь профиля дурака (обычный прогон) ===\n');
  const { строки, провалов } = прогнать(ПУТЬ_GAME_JS_ОРИГИНАЛ);
  строки.forEach(с => console.log(с));
  console.log('');
  console.log('Итого проверок: ' + строки.length + ', провалов: ' + провалов);
  process.exit(провалов > 0 ? 1 : 0);
} else {
  console.log('=== Дверь профиля дурака (ЛОМАЮЩИЙ прогон --сломать) ===\n');

  const оригинал = fs.readFileSync(ПУТЬ_GAME_JS_ОРИГИНАЛ, 'utf8');

  /** Испортить оригинал одной подменой текста и прогнать проверки по КОПИИ
   *  во временной папке — настоящий js/game.js при этом не трогается вовсе.
   *  Возвращает { результат, путьКопии } либо null, если искомый текст
   *  не нашёлся (приём в game.js поменялся — порчу нужно обновить). */
  function прогнатьНаКопииСПорчей(имяПорчи, искомое, замена) {
    if (оригинал.indexOf(искомое) === -1) {
      console.log('ОШИБКА (' + имяПорчи + '): порча не применилась — в js/game.js не нашлась ожидаемая строка.');
      console.log('Приём в game.js поменялся — обновите порчу в этом тесте.');
      return null;
    }
    const испорченный = оригинал.split(искомое).join(замена);
    if (испорченный === оригинал) {
      console.log('ОШИБКА (' + имяПорчи + '): замена не применилась (внутренняя ошибка теста).');
      return null;
    }
    const временнаяПапка = fs.mkdtempSync(path.join(os.tmpdir(), 'дверь-профиля-дурака-' + имяПорчи + '-'));
    const путьКопии = path.join(временнаяПапка, 'game.js');
    fs.writeFileSync(путьКопии, испорченный, 'utf8');
    console.log('Порча «' + имяПорчи + '»: копия — ' + путьКопии + ' (настоящий js/game.js не тронут).');

    let результат;
    try {
      результат = прогнать(путьКопии);
    } finally {
      try {
        fs.unlinkSync(путьКопии);
        fs.rmdirSync(временнаяПапка);
      } catch (е) { /* уборка временной папки необязательна для итога прогона */ }
    }
    return { результат: результат, путьКопии: путьКопии };
  }

  const непойманные = [];

  // 1) Откат двери профиля к старому поведению (как будто задача Э7а не сделана).
  console.log('\n--- 1) Порча: «открытьПрофильДурака» без новой двери в ЭкранПрофиля ---');
  const итог1 = прогнатьНаКопииСПорчей(
    'дверь-профиля',
    "function открытьПрофильДурака() {\r\n" +
    "  if (window.ЭкранПрофиля && typeof window.ЭкранПрофиля.открыть === 'function') {\r\n" +
    "    window.ЭкранПрофиля.открыть('дурак');\r\n" +
    "    return;\r\n" +
    "  }\r\n" +
    "  экранОткудаПришли = запомнитьГдеБыли();\r\n" +
    "  показатьМойСчёт();\r\n" +
    "}",
    "function открытьПрофильДурака() {\r\n" +
    "  экранОткудаПришли = запомнитьГдеБыли();\r\n" +
    "  показатьМойСчёт();\r\n" +
    "}"
  );
  if (!итог1) {
    непойманные.push('1) дверь-профиля: порча не применилась');
  } else {
    итог1.результат.строки.forEach(с => console.log(с));
    console.log('Провалов на копии: ' + итог1.результат.провалов);
    const ожидание = 'а) клик зовёт window.ЭкранПрофиля.открыть ровно один раз';
    const поймали = итог1.результат.строки.some(с => с.indexOf('ПЛОХО') === 0 && с.indexOf(ожидание) !== -1);
    if (!поймали) непойманные.push('1) дверь-профиля: ожидаемая проверка не покраснела («' + ожидание + '»)');
  }

  // 2) «запомнитьГдеБыли» всегда возвращает лобби — имитация найденной беды
  //    («из профиля «Как я играю» может вернуть в лобби, а не в профиль»).
  console.log('\n--- 2) Порча: «запомнитьГдеБыли» игнорирует DOM и всегда отдаёт лобби ---');
  const итог2 = прогнатьНаКопииСПорчей(
    'запомнить-где-были',
    "function запомнитьГдеБыли() {\r\n" +
    "  const итог = эл('экран-результата');",
    "function запомнитьГдеБыли() {\r\n" +
    "  return { экран: ЭКРАН_ЛОББИ, плашкаИтога: false };   // ЛОМАЮЩИЙ ПРОГОН: подмена для теста\r\n" +
    "  const итог = эл('экран-результата');"
  );
  if (!итог2) {
    непойманные.push('2) запомнить-где-были: порча не применилась');
  } else {
    итог2.результат.строки.forEach(с => console.log(с));
    console.log('Провалов на копии: ' + итог2.результат.провалов);
    const ожидание = 'в) «Назад» вернул в профиль, а не в лобби';
    const поймали = итог2.результат.строки.some(с => с.indexOf('ПЛОХО') === 0 && с.indexOf(ожидание) !== -1);
    if (!поймали) непойманные.push('2) запомнить-где-были: ожидаемая проверка не покраснела («' + ожидание + '»)');
  }

  // 3) ЭКРАНЫ_ПОВЕРХ без профиля — правка ревьюера отменена.
  console.log('\n--- 3) Порча: «экран-профиля-игрока» убран из ЭКРАНЫ_ПОВЕРХ ---');
  const итог3 = прогнатьНаКопииСПорчей(
    'экраны-поверх',
    "const ЭКРАНЫ_ПОВЕРХ = ['экран-правил', 'экран-рекордов', 'экран-рейтинга', 'экран-рейтинга-игроков',\r\n" +
    "  // Профиль (js/профиль-экран.js) — тот же случай: открыт поверх комнаты\r\n" +
    "  // ожидания партии с другом, опрос сети не должен выдёргивать из него\r\n" +
    "  // (нашёл ревьюер, тот же приём, что у правил и рекордов).\r\n" +
    "  'экран-профиля-игрока'];",
    "const ЭКРАНЫ_ПОВЕРХ = ['экран-правил', 'экран-рекордов', 'экран-рейтинга', 'экран-рейтинга-игроков'];"
  );
  if (!итог3) {
    непойманные.push('3) экраны-поверх: порча не применилась');
  } else {
    итог3.результат.строки.forEach(с => console.log(с));
    console.log('Провалов на копии: ' + итог3.результат.провалов);
    const ожидание = 'г) «служебныйЭкранОткрыт» видит открытый профиль';
    const поймали = итог3.результат.строки.some(с => с.indexOf('ПЛОХО') === 0 && с.indexOf(ожидание) !== -1);
    if (!поймали) непойманные.push('3) экраны-поверх: ожидаемая проверка не покраснела («' + ожидание + '»)');
  }

  console.log('');
  if (непойманные.length === 0) {
    console.log('ИТОГ ЛОМАЮЩЕГО ПРОГОНА: все три порчи пойманы.');
    process.exit(0);
  } else {
    console.log('ИТОГ ЛОМАЮЩЕГО ПРОГОНА: ПРОВЕРКА СЛЕПАЯ — не покраснели: ' + JSON.stringify(непойманные));
    process.exit(1);
  }
}
