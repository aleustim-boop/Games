'use strict';
/* =====================================================================
   ЛОББИ ДУРАКА, ЕСЛИ игры/дурак/дурак-путь.js НЕ ДОЕХАЛ.

   Зачем. Лобби и три шага живут в отдельном файле игры/дурак/дурак-путь.js. Файл
   может не доехать до телефона: сбой связи, старая страница в памяти
   Telegram (разметка новая, а файла ещё нет). Тогда кнопки лобби
   оживляет «запасной вход» в игры/дурак/game.js (подключитьЗапаснойВходЛобби):
   «Играть с ботами» сразу садит за прежний стол, «‹» ведёт на витрину,
   «⋯» открывает лист. Без него лобби было бы мёртвым — даже выйти нечем.

   Что делает. Не пускает игры/дурак/дурак-путь.js и нажимает кнопки лобби
   настоящими нажатиями — в обычном браузере и в поддельном Telegram 8.0
   (там «‹» и «⋯» спрятаны, уходят стрелкой Telegram и пунктом «Настройки»).

   Ломающий прогон («сломать»): страница получает игры/дурак/game.js, в котором
   вызов запасного входа вырезан. Проверка обязана покраснеть — иначе
   она не видит того, ради чего написана.

   Запуск (страничный сервер уже поднят):
       node tests/лобби-без-файла-пути.js [порт] [сломать] [порт-комнат]
       node tests/лобби-без-файла-пути.js [порт] сломать

   Сервер комнат. Без адреса «?сервер=» страница по умолчанию стучится
   на боевой 127.0.0.1:8790, там на этом стенде никого нет (боевой сервер
   переехал на ВМ) — консоль красит ERR_CONNECTION_REFUSED. Подделывать
   fulfill'ом ответ на 8790 — маскировка (ERR_CONNECTION_REFUSED прятался бы
   тихо). Вместо этого поднимаем СВОЙ сервер комнат «--без-памяти» на
   свободном порту (по рецепту tests/все-экраны-в-полном-экране.js) и
   говорим странице его адрес тем же приёмом «index.html?сервер=», что и
   tests/найти-игру-гасит-опрос-столов.js. Боевой 8790 не трогаем.
   ===================================================================== */
const fs = require('fs');
const path = require('path');
const { spawn } = require('child_process');
const { chromium, подготовитьПодделку, перехватить } = require(path.join(__dirname, 'браузер-робот.js'));

const КОРЕНЬ = path.join(__dirname, '..');
const ПОРТ = /^\d+$/.test(process.argv[2] || '') ? process.argv[2] : '8080';
const АДРЕС = 'http://127.0.0.1:' + ПОРТ + '/';
const СЛОМАТЬ = process.argv.indexOf('сломать') !== -1;
const ПОРТ_КОМНАТ = /^\d+$/.test(process.argv[3] || '') ? Number(process.argv[3]) : 8792;
const АДРЕС_КОМНАТ = 'http://127.0.0.1:' + ПОРТ_КОМНАТ;

/** Свой сервер комнат «--без-памяти» на свободном порту — боевой 8790 не трогаем. */
function поднятьКомнаты() {
  return new Promise(function (готово, беда) {
    const дитя = spawn('node', [path.join(КОРЕНЬ, 'server', 'сервер.js'), String(ПОРТ_КОМНАТ), '--без-памяти']);
    let вывод = '';
    const срок = setTimeout(() => { дитя.kill(); беда(new Error('сервер комнат не поднялся за 15 секунд')); }, 15000);
    дитя.stdout.on('data', (кусок) => {
      вывод += кусок;
      if (/работает на порту/.test(вывод)) { clearTimeout(срок); готово(дитя); }
    });
    дитя.on('error', беда);
  });
}

let провалов = 0;
function надо(условие, слова) {
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}
const спать = (мс) => new Promise((г) => setTimeout(г, мс));

/* Для ломающего прогона: игры/дурак/game.js без вызова запасного входа. Сколько
   вызовов вырезано — считаем: ноль значит, что ломать было нечего, и
   такой «красный» прогон ничего бы не доказал. */
const ИГРА = fs.readFileSync(path.join(__dirname, '..', 'игры', 'дурак', 'game.js'), 'utf8');
let вырезано = 0;
const ИГРА_СЛОМАННАЯ = ИГРА.replace(/подключитьЗапаснойВходЛобби\(\);/g, () => { вырезано++; return '/* вырезано стендом */;'; });

async function открыть(браузер, вТелеграме) {
  const окно = await браузер.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
  const стр = await окно.newPage();
  const красные = [];
  const предупреждения = [];
  стр.on('pageerror', (о) => красные.push('падение: ' + о.message));
  стр.on('console', (м) => {
    const откуда = (м.location && м.location() && м.location().url) || '';
    let адрес = откуда;
    try { адрес = decodeURIComponent(откуда); } catch (о) { /* как есть */ }
    if (м.type() === 'warning') предупреждения.push(м.text());
    if (м.type() !== 'error') return;
    // Отказы, которые устроили мы сами: скрипт Telegram и файл пути.
    if (/telegram-web-app\.js|дурак-путь\.js/.test(м.text() + ' ' + адрес)) return;
    красные.push('консоль: ' + м.text());
  });
  if (вТелеграме) await подготовитьПодделку(стр, { версия: '8.0', полныйЭкран: 'дают' });
  let непущено = 0;
  await перехватить(стр, /.*/, (путь, запрос, адрес) => {
    // Не пускаем игры/дурак/дурак-путь.js — это наша основная цель.
    if (/дурак-путь\.js/.test(адрес)) { непущено++; путь.abort(); return; }
    // Для ломающего прогона подменяем game.js.
    if (СЛОМАТЬ && /\/игры\/дурак\/game\.js/.test(адрес)) {
      путь.fulfill({ status: 200, contentType: 'application/javascript; charset=utf-8', body: ИГРА_СЛОМАННАЯ });
      return;
    }
    // Всё остальное пускаем дальше.
    путь.continue();
  });
  await стр.goto(АДРЕС + '?сервер=' + АДРЕС_КОМНАТ);
  await стр.waitForFunction(() => typeof показатьЛоббиДурака === 'function', null, { timeout: 10000 });
  await спать(500);
  return { окно, стр, красные, предупреждения, непущено: () => непущено };
}

const видим = (стр) => стр.evaluate(() => (document.querySelector('.экран.экран--виден') || {}).id || '');
const листОткрыт = (стр) => стр.evaluate(() => {
  const л = document.getElementById('лист-игры');
  return Boolean(л && !л.classList.contains('скрыт'));
});

(async () => {
  if (СЛОМАТЬ) console.log('РЕЖИМ «СЛОМАТЬ»: вызов запасного входа вырезан из игры/дурак/game.js (вырезано ' + вырезано + ') — проверка обязана покраснеть.\n');
  console.log('Поднимаю свой сервер комнат «--без-памяти» на ' + ПОРТ_КОМНАТ + ' (боевой 8790 не трогаем)…');
  const комнаты = await поднятьКомнаты();
  const браузер = await chromium.launch();

  console.log('=== 1. Обычный браузер, игры/дурак/дурак-путь.js не пустили ===');
  {
    const { окно, стр, красные, предупреждения, непущено } = await открыть(браузер, false);
    надо(непущено() >= 1, 'файл пути и правда не пустили (отказов: ' + непущено() + ')');
    надо(await стр.evaluate(() => typeof window.ДуракПуть === 'undefined'), 'window.ДуракПуть нет — проверяем именно запасной вход');
    await стр.click('#кнопка-игра-дурак');
    await спать(300);
    надо(await видим(стр) === 'экран-лобби', '«Дурак» на витрине открыл лобби (' + await видим(стр) + ')');

    await стр.click('#экран-лобби [data-путь="ещё"]');
    await спать(300);
    надо(await листОткрыт(стр), '«⋯» в лобби открыл лист');
    await стр.keyboard.press('Escape');
    await спать(200);
    if (await листОткрыт(стр)) await стр.evaluate(() => закрытьЛистИгры(false));

    await стр.click('#экран-лобби [data-путь="назад"]');
    await спать(300);
    надо(await видим(стр) === 'экран-витрины', '«‹» в лобби вернула на витрину (' + await видим(стр) + ')');
    // Не вернула (лобби мертво) — дальше идём сами, чтобы досказать остальное.
    if (await видим(стр) !== 'экран-витрины') await стр.evaluate(() => показатьЭкран('экран-витрины'));

    await стр.click('#кнопка-игра-дурак');
    await спать(300);
    await стр.click('#лобби-боты');
    await спать(1200);
    const стол = await стр.evaluate(() => ({
      экран: (document.querySelector('.экран.экран--виден') || {}).id || '',
      карт: document.querySelectorAll('#карты-человека .карта').length
    }));
    надо(стол.экран === 'экран-игры' && стол.карт >= 6, '«Играть с ботами» без шагов сразу посадил за стол: ' + JSON.stringify(стол));

    const предупреждение = предупреждения.filter((т) => /дурак-путь\.js/.test(т));
    console.log('  предупреждение для разработчика: ' + (предупреждение[0] || '(нет)'));
    надо(красные.length === 0, 'красных строк нет' + (красные.length ? ': ' + красные.slice(0, 3).join(' | ') : ''));
    await окно.close();
  }

  console.log('\n=== 2. Поддельный Telegram 8.0, игры/дурак/дурак-путь.js не пустили ===');
  {
    const { окно, стр, красные, непущено } = await открыть(браузер, true);
    надо(непущено() >= 1, 'файл пути и правда не пустили (отказов: ' + непущено() + ')');
    await стр.click('#кнопка-игра-дурак');
    await спать(300);
    надо(await видим(стр) === 'экран-лобби', '«Дурак» открыл лобби');
    await стр.evaluate(() => window.ПоддельныйТелеграм.нажатьНастройки());
    await спать(300);
    надо(await листОткрыт(стр), 'пункт «Настройки» Telegram в лобби открыл лист');
    await стр.evaluate(() => закрытьЛистИгры(false));
    await стр.evaluate(() => window.ПоддельныйТелеграм.нажатьНазад());
    await спать(300);
    надо(await видим(стр) === 'экран-витрины', 'стрелка «Назад» Telegram из лобби — на витрину (' + await видим(стр) + ')');
    if (await видим(стр) !== 'экран-витрины') await стр.evaluate(() => показатьЭкран('экран-витрины'));
    await стр.click('#кнопка-игра-дурак');
    await спать(300);
    await стр.click('#лобби-боты');
    await спать(1200);
    надо(await видим(стр) === 'экран-игры', '«Играть с ботами» посадил за стол (' + await видим(стр) + ')');
    надо(красные.length === 0, 'красных строк нет' + (красные.length ? ': ' + красные.slice(0, 3).join(' | ') : ''));
    await окно.close();
  }

  await браузер.close();
  комнаты.kill();
  if (СЛОМАТЬ && вырезано === 0) {
    console.log('\nВНИМАНИЕ: ломать было нечего — вызова запасного входа в игры/дурак/game.js не нашлось. Ломающий прогон ничего не доказал.');
    process.exit(2);
  }
  console.log('\nИтог: провалов ' + провалов);
  process.exit(провалов ? 1 : 0);
})().catch((о) => { console.error('проверка упала: ' + (о && о.stack || о)); process.exit(2); });
