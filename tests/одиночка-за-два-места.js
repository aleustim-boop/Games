const раскладки = [
  { имя: 'парами, полная раздача',            набор: { игроков: 4, парами: true }, карт: 6 },
  { имя: 'парами, концовка по 3 карты',       набор: { игроков: 4, парами: true }, карт: 3 },
  { имя: 'парами, концовка по 2 карты',       набор: { игроков: 4, парами: true }, карт: 2 },
  { имя: 'парами+перевод, полная раздача',    набор: { игроков: 4, парами: true, переводной: true }, карт: 6 },
  { имя: 'парами+перевод, концовка по 3',     набор: { игроков: 4, парами: true, переводной: true }, карт: 3 },
  { имя: 'парами+перевод, концовка по 2',     набор: { игроков: 4, парами: true, переводной: true }, карт: 2 }
];
const манеры = ['обычный', 'сложный', 'наугад'];

const итог = {
  партий: 0,
  сВыбыванием: 0,
  подходов: 0,
  одиночкаОтбивался: 0,
  вечноНаОдного: [],       // партии, где одиночка нападал только на одного соперника
  длинныхАтакОдиночки: 0,  // партий, где одиночка нападал хотя бы четырежды
  ктоТоНеУчаствовал: [],   // партии, где кто-то из троих не получил ни хода, ни защиты
  переводов: 0,
  уперлисьВПотолок: 0,
  беды: []
};

let номер = 0;
for (const раскладка of раскладки) {
  for (const манера of манеры) {
    for (let н = 1; н <= ПАРТИЙ; н++) {
      номер++;
      const зерно = (номер * 7919 + 13) | 0;
      const набор = Object.assign({ сложность: манера === 'наугад' ? 'обычный' : манера }, раскладка.набор);
      const р = сыгратьПартию(набор, зерно, манера, раскладка.карт);
      итог.партий++;
      итог.переводов += р.переводов;
      if (р.уперласьВПотолок) итог.уперлисьВПотолок++;
      for (const б of р.беды) {
        итог.беды.push(раскладка.имя + ' — ' + манера + ', партия №' + н + ': ' + б);
      }
      if (!р.выбываниеБыло) continue;
      итог.сВыбыванием++;
      итог.подходов += р.подходовПослеВыбывания;
      итог.одиночкаОтбивался += р.защищалсяОдиночка;

      /* Нападал ли одиночка на обоих соперников. Строгим правилом это быть
         не может: он вправе несколько подходов подряд ходить с одного и того
         же своего места. А вот если он НИ В ОДНОЙ длинной партии не сходил
         на второго соперника — значит место выбывшего опять выпало из круга,
         и это ровно та беда, на которую жаловался владелец. */
      const жертвы = Object.keys(р.жертвыОдиночки);
      const атакОдиночки = жертвы.reduce(function (с, и) { return с + р.жертвыОдиночки[и]; }, 0);
      if (атакОдиночки >= 4) {
        итог.длинныхАтакОдиночки++;
        if (жертвы.length === 1) {
          итог.вечноНаОдного.push(раскладка.имя + ' — ' + манера + ', партия №' + н +
            ': одиночка нападал ' + атакОдиночки + ' раз и всегда на «' + жертвы[0] + '»');
        }
      }

      // Кто-то из живых не получил ни одного хода и ни одной защиты.
      if (р.подходовПослеВыбывания >= 6) {
        const п = р.партия;
        for (const имя of п.игроки) {
          if (!живой(п, имя)) continue;
          if (!р.ктоАтаковал[имя] && !р.ктоЗащищался[имя]) {
            итог.ктоТоНеУчаствовал.push(раскладка.имя + ' — ' + манера + ', партия №' + н +
              ': «' + имя + '» за ' + р.подходовПослеВыбывания +
              ' подходов после выбывания ни разу не ходил и ни разу не отбивался');
          }
        }
      }
    }
  }
}

console.log('=== Одиночка за два места: парный стол после выбывания ===');
console.log('партий сыграно: ' + итог.партий + ', из них с выбыванием: ' + итог.сВыбыванием);
console.log('подходов после выбывания: ' + итог.подходов + ', переводов сделано: ' + итог.переводов);
