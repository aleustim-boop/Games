/* =====================================================================
   ОДИНОЧКА ЗА ДВА МЕСТА — проверка парного стола после выбывания.

   ОТКУДА ЗАДАЧА. Жалоба владельца: «в игре 2 на 2, если кто-то вылетает,
   играем втроём, а по факту играют двое, третий втыкает». Причина была
   в том, что игра выкидывала место выбывшего из круга. По правилам место
   остаётся, и за него играет напарник — значит, одиночка нападает то
   на одного соперника, то на другого.

   ЧЕМ ЭТА ПРОВЕРКА ОТЛИЧАЕТСЯ ОТ ПРОЧИХ. Она не спрашивает у игры, кто
   должен ходить, — она считает это сама, своими руками, по словам правил,
   и потом СВЕРЯЕТ с игрой. Плюс, и это главное, она смотрит на то, что
   видит живой человек за столом:

     1) участвуют ли после выбывания все трое (это и есть жалоба владельца);
     2) нападает ли одиночка на ОБОИХ соперников, а не вечно на одного;
     3) как часто отбиваться выпадает именно одиночке (если почти всегда —
        значит круг снова свернулся на двоих);
     4) не теряются и не удваиваются ли карты (одиночка играет за два места,
        и без присмотра он добирал бы из колоды дважды за круг);
     5) после перевода у нового защитника хватает карт на всё, что на столе
        (иначе перевод разрешён, а отбиваться нечем);
     6) никто не нападает на себя и на своего напарника.

   ЗАПУСК:
     node tests/одиночка-за-два-места.js [сколько партий на раскладку] [путь к своей копии game.js]

   Второй довод нужен для КОНТРОЛЯ: подсовываем нарочно сломанную копию
   игры и смотрим, что проверка её ловит. Проверка, которая никогда
   не краснеет, ничего и не доказывает.
   ===================================================================== */

const path = require('path');
const ПАРТИЙ = Number(process.argv[2]) || 200;
const ПУТЬ_СВОЙ = process.argv[3] && process.argv[3] !== '-' ? path.resolve(process.argv[3]) : '';
const игра = require(ПУТЬ_СВОЙ || path.join(__dirname, '..', 'js', 'game.js'));

const генератор = require(path.join(__dirname, 'общий-генератор.js'));
генератор.захватитьСлучайность();

const ПОТОЛОК_ХОДОВ = 900;

/* --------------------------------------------------------------------
   СВОЙ СЧЁТ ПРАВИЛ. Ниже правила переписаны заново по словам, а не взяты
   из игры. Если игра и эта запись разойдутся — сверка это покажет.
   -------------------------------------------------------------------- */

/** Жив ли игрок (не вышел ли без карт). */
function живой(п, имя) {
  return (п.выбывшие || []).indexOf(имя) === -1;
}

/** Напарник по рассадке: свои сидят через одного. Вне игры парами напарников нет. */
function мойНапарник(п, имя) {
  if (!п.парами) return null;
  const место = п.игроки.indexOf(имя);
  if (место === -1) return null;
  return п.игроки[(место + 2) % п.игроки.length];
}

/**
 * Кто играет за это место. Место выбывшего не исчезает: за него играет
 * напарник. Если напарника нет или он тоже вышел — место пустое (null).
 */
function заМесто(п, место) {
  const имя = п.игроки[место];
  if (имя === undefined) return null;
  if (живой(п, имя)) return имя;
  const нап = мойНапарник(п, имя);
  return нап && живой(п, нап) ? нап : null;
}

/** Свои ли это двое: сам себе свой, и напарник свой. */
function свои(п, один, другой) {
  return один === другой || мойНапарник(п, один) === другой;
}

/** С какого места отбиваются, если нападают с названного: следующее занятое чужое. */
function моёМестоЗащиты(п, местоАтаки) {
  const всего = п.игроки.length;
  const нападающий = заМесто(п, местоАтаки % всего);
  for (let шаг = 1; шаг < всего; шаг++) {
    const м = (местоАтаки + шаг) % всего;
    const кто = заМесто(п, м);
    if (!кто) continue;
    if (нападающий && свои(п, нападающий, кто)) continue;
    return м;
  }
  return местоАтаки % всего;
}

/** Кто отбивается по моему счёту. */
function мойЗащитник(п) {
  const м = моёМестоЗащиты(п, Number(п.местоАтаки) || 0);
  return заМесто(п, м) || п.игроки[м];
}

/* --------------------------------------------------------------------
   Игроки-роботы для прогона. Ходят по-разному, чтобы состояний
   перебиралось больше.
   -------------------------------------------------------------------- */

/** Ход наугад: так партия забредает туда, куда обычный бот не ходит. */
function ходНаугад(п, кто, случайное) {
  const фаза = игра.фаза(п);
  const рука = п.руки[кто] || [];
  if (фаза === 'защита') {
    // Иногда пробуем перевести — переводной стол ради этого и проверяем.
    if (п.переводной && случайное() < 0.5) {
      for (let i = 0; i < рука.length; i++) {
        if (игра.можноПеревести(п, рука[i]) && игра.перевести(п, i)) return;
      }
    }
    const варианты = [];
    п.стол.forEach(function (пара, iП) {
      if (пара.защита) return;
      рука.forEach(function (к, iК) {
        if (игра.бьёт(к, пара.атака, п.козырь)) варианты.push([iП, iК]);
      });
    });
    if (варианты.length === 0 || случайное() < 0.25) { игра.объявитьБеру(п); return; }
    const в = варианты[Math.floor(случайное() * варианты.length)];
    игра.отбить(п, в[0], в[1]);
    return;
  }
  const годные = [];
  for (let i = 0; i < рука.length; i++) if (игра.можноПоложить(п, рука[i])) годные.push(i);
  if (годные.length === 0 || (фаза !== 'атака' && случайное() < 0.4)) { игра.пас(п, кто); return; }
  игра.положитьВАтаку(п, кто, годные[Math.floor(случайное() * годные.length)]);
}

/* --------------------------------------------------------------------
   Одна партия. Возвращает разбор: что случилось после выбывания.
   -------------------------------------------------------------------- */

function сыгратьПартию(настройки, зерно, манера, карт_в_руке) {
  генератор.поставитьЗерно(зерно);
  const случайное = генератор.создатьПоток(зерно ^ 0x5f3a);
  const п = игра.создатьПартию(настройки);

  // Короткая раздача: лишние карты сразу в отбой — так выбывание наступает быстрее.
  if (карт_в_руке && карт_в_руке < 6) {
    for (const имя of п.игроки) {
      while (п.руки[имя].length > карт_в_руке) п.отбой.push(п.руки[имя].pop());
    }
    while (п.колода.length > 1) п.отбой.push(п.колода.shift());
  }

  // Сколько карт в партии всего — этому числу обязана равняться сумма всегда.
  const всегоКарт = п.колода.length + п.отбой.length +
    п.игроки.reduce(function (с, имя) { return с + п.руки[имя].length; }, 0);

  const беды = [];
  const разбор = {
    подходовПослеВыбывания: 0,
    защищалсяОдиночка: 0,
    ктоАтаковал: {},       // имя → сколько подходов начал
    ктоЗащищался: {},      // имя → сколько подходов отбивался
    жертвыОдиночки: {},    // на кого одиночка нападал (когда одиночка — атакующий)
    выбываниеБыло: false,
    переводов: 0,
    беды: беды,
    доиграна: false
  };

  let шагов = 0;
  let подходЗаписан = false;
  let кандидат = null;

  while (!п.завершена && шагов++ < ПОТОЛОК_ХОДОВ) {
    const одиночка = п.парами ? найтиОдиночку(п) : null;

    /* ---- сверка «кто отбивается» на каждом шаге ---- */
    const ждётЗащиты = игра.защищается(п);
    const мой = мойЗащитник(п);
    if (ждётЗащиты !== мой) {
      беды.push('игра считает, что отбивается «' + ждётЗащиты + '», а по правилам — «' + мой +
        '» (место атаки ' + п.местоАтаки + ', выбыли: ' + (п.выбывшие || []).join(',') + ')');
      break;
    }
    // Нападать на себя и на своего нельзя никогда.
    const кто_атакует = п.атакует;
    if (свои(п, кто_атакует, ждётЗащиты)) {
      беды.push('нападают на своего: «' + кто_атакует + '» против «' + ждётЗащиты + '»');
      break;
    }
    // Имя атакующего обязано совпадать с тем, кто играет за место атаки.
    const заМестоАтаки = заМесто(п, Number(п.местоАтаки) || 0);
    if (заМестоАтаки && заМестоАтаки !== кто_атакует) {
      беды.push('за место ' + п.местоАтаки + ' играет «' + заМестоАтаки +
        '», а нападающим значится «' + кто_атакует + '»');
      break;
    }

    /* ---- сохранность карт ---- */
    const сумма = п.колода.length + п.отбой.length +
      п.игроки.reduce(function (с, имя) { return с + п.руки[имя].length; }, 0) +
      п.стол.reduce(function (с, пара) { return с + 1 + (пара.защита ? 1 : 0); }, 0);
    if (сумма !== всегоКарт) {
      беды.push('карты потерялись или размножились: было ' + всегоКарт + ', стало ' + сумма +
        ' (выбыли: ' + (п.выбывшие || []).join(',') + ')');
      break;
    }
    if (беды.length) break;

    /* ---- запись подхода ---- */
    if (п.стол.length === 0) {
      подходЗаписан = false;
      кандидат = { атакующий: кто_атакует, защитник: ждётЗащиты };
    } else if (!подходЗаписан && кандидат) {
      подходЗаписан = true;
      if (разбор.выбываниеБыло) {
        разбор.подходовПослеВыбывания++;
        разбор.ктоАтаковал[кандидат.атакующий] = (разбор.ктоАтаковал[кандидат.атакующий] || 0) + 1;
        разбор.ктоЗащищался[кандидат.защитник] = (разбор.ктоЗащищался[кандидат.защитник] || 0) + 1;
        if (одиночка && кандидат.защитник === одиночка) разбор.защищалсяОдиночка++;
        if (одиночка && кандидат.атакующий === одиночка) {
          разбор.жертвыОдиночки[кандидат.защитник] = (разбор.жертвыОдиночки[кандидат.защитник] || 0) + 1;
        }
      }
    }

    /* ---- сам ход ---- */
    const ходит = игра.ктоХодит(п);
    if (!ходит) { беды.push('нажать некому: игра не назвала, чьё слово'); break; }
    if (!живой(п, ходит)) { беды.push('слово отдано выбывшему «' + ходит + '»'); break; }

    const былоМестоАтаки = Number(п.местоАтаки);
    const былаФаза = игра.фаза(п);
    const былоНаСтоле = п.стол.length;
    const рукаБыла = п.руки[ходит].length;
    const пасовБыло = (п.пасы || []).length;
    const бралДо = п.берёт;
    /* Слепок рук перед ходом — чтобы после добора проверить, что никто
       не вытянул из колоды лишнего. Одиночка играет за два места, и если
       круг посчитает его дважды, он доберёт вдвое больше — а сумма карт
       при этом сойдётся, и по ней такую беду не поймать. */
    const рукиДо = {};
    for (const имя of п.игроки) рукиДо[имя] = п.руки[имя].length;
    const бравший = п.берёт ? ждётЗащиты : null;
    const местоЗащитыДо = моёМестоЗащиты(п, Number(п.местоАтаки) || 0);

    if (манера === 'наугад') ходНаугад(п, ходит, случайное);
    else игра.ходБота(п, ходит, манера);

    /* ---- перевод: у нового защитника обязано хватить карт ---- */
    const сталоМесто = Number(п.местоАтаки);
    if (былаФаза === 'защита' && п.стол.length === былоНаСтоле + 1 && сталоМесто !== былоМестоАтаки) {
      разбор.переводов++;
      const новыйЗащитник = игра.защищается(п);
      const укогоКарт = (п.руки[новыйЗащитник] || []).length;
      if (новыйЗащитник === ходит) {
        беды.push('перевод вернулся к переводившему: «' + ходит + '» отбивается сам от себя');
      } else if (свои(п, ходит, новыйЗащитник)) {
        беды.push('перевод ушёл своему: «' + ходит + '» перевёл на напарника «' + новыйЗащитник + '»');
      } else if (укогоКарт < п.стол.length) {
        беды.push('перевод разрешили, а отбиваться нечем: на столе ' + п.стол.length +
          ' карт, а у «' + новыйЗащитник + '» в руке ' + укогоКарт);
      }
    }

    /* ---- подход закончился: куда ушёл ход ----
       Самая строгая проверка всей этой работы. Правило простое и одно
       на все столы: отбился — нападает ЕГО МЕСТО, взял — следующее место
       за ним. Пустые места (там, где выбывший без живого напарника)
       пропускаем.

       Считать надо именно по местам. По именам беда не видна вовсе:
       у одиночки два места, и если одно из них выпадет из круга, отвечать
       на вопрос «кто отбивается» игра будет тем же самым именем — а ход
       при этом станет ходить по укороченному кругу, и второй соперник
       одиночки в игре участвовать перестанет. Ровно на это и жаловался
       владелец. */
    if (былоНаСтоле > 0 && п.стол.length === 0 && !п.завершена) {
      const всего = п.игроки.length;
      let ожидание = (местоЗащитыДо + (бралДо ? 1 : 0)) % всего;
      for (let шаг = 0; шаг < всего && !заМесто(п, ожидание); шаг++) {
        ожидание = (ожидание + 1) % всего;
      }
      if (Number(п.местоАтаки) !== ожидание) {
        беды.push('после подхода ход ушёл не туда: отбивалось место ' + местоЗащитыДо +
          ' и защитник ' + (бралДо ? 'ВЗЯЛ' : 'отбился') + ', значит нападать должно место ' +
          ожидание + ' («' + заМесто(п, ожидание) + '»), а игра поставила место ' +
          п.местоАтаки + ' («' + п.атакует + '»); выбыли: ' + (п.выбывшие || []).join(',') || 'никто');
      }
    }

    /* ---- подход закончился: проверяем добор ---- */
    if (былоНаСтоле > 0 && п.стол.length === 0) {
      for (const имя of п.игроки) {
        /* Сколько карт у человека может оказаться по-честному: либо шесть
           (добор), либо сколько было (добор руку не укорачивает), либо
           сколько было плюс весь стол — это про того, кто сказал «Беру». */
        const взялСоСтола = имя === бравший ? былоНаСтоле * 2 : 0;
        const потолок = Math.max(6, рукиДо[имя] + взялСоСтола);
        if (п.руки[имя].length > потолок) {
          беды.push('после подхода у «' + имя + '» стало ' + п.руки[имя].length +
            ' карт (было ' + рукиДо[имя] + ', брал со стола: ' + (имя === бравший ? 'да' : 'нет') +
            ') — похоже, добрал из колоды за два места сразу');
        }
      }
      if (беды.length) break;
    }

    /* ---- игра встала: ход был, а не изменилось ровным счётом ничего ---- */
    const ничегоНеИзменилось =
      п.стол.length === былоНаСтоле &&
      Number(п.местоАтаки) === былоМестоАтаки &&
      п.руки[ходит].length === рукаБыла &&
      игра.фаза(п) === былаФаза &&
      (п.пасы || []).length === пасовБыло &&
      п.берёт === бралДо &&
      !п.завершена;
    if (ничегоНеИзменилось) {
      беды.push('ход «' + ходит + '» ничего не изменил — партия встала (фаза ' + былаФаза + ')');
      break;
    }

    if ((п.выбывшие || []).length > 0) разбор.выбываниеБыло = true;
    if (беды.length) break;
  }

  разбор.доиграна = п.завершена;
  if (!п.завершена && !беды.length) {
    // Ходящая по кругу партия — не поломка (в правилах нет слова «ничья»),
    // но её надо отличать от зависшей: об этом скажет отдельная строка отчёта.
    разбор.уперласьВПотолок = true;
  }
  разбор.партия = п;
  return разбор;
}

/** Кто остался один против пары: живых трое и у одного из них напарник выбыл. */
function найтиОдиночку(п) {
  if (!п.парами) return null;
  for (const имя of п.игроки) {
    if (!живой(п, имя)) continue;
    const нап = мойНапарник(п, имя);
    if (нап && !живой(п, нап)) return имя;
  }
  return null;
}

