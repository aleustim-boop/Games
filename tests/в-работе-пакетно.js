/*
  Проверка для штаб/в-работе.js: программу нельзя звать часто без толку.

  Аудит штаба (16 сентября, штаб/аудит-2026-09-16.md, пункт Р5) нашёл 312
  вызовов программы за неделю при 192 этапах. Причина была в самой защите:
  она пропускала перезапись ЗАДАЧИ.md, только если содержимое совпало И
  прошло меньше 10 минут. Стоило прошедшему времени перевалить за 10 минут —
  файл переписывался заново, даже если список работ не поменялся ни на
  символ. Эта проверка ловит именно такой повтор.

  Два прогона в одном файле:

    node tests/в-работе-пакетно.js            — обычный: несколько вызовов
      подряд с одной и той же работой (в том числе с искусственно
      состаренной строкой времени в ЗАДАЧИ.md) не должны переписывать файл
      больше одного раза — только на самой первой записи.

    node tests/в-работе-пакетно.js --сломать  — ломающий: между вызовами
      работа реально меняется, и файл обязан перезаписываться каждый раз.
      Если защита слишком грубая (например, вообще перестала писать после
      первого раза), этот прогон покраснеет.

  Оба прогона работают с настоящими штаб/в-работе.json и ЗАДАЧИ.md — других
  путей программа не знает (они зашиты через __dirname). Поэтому перед
  работой оригиналы читаются в память, а в конце — что бы ни случилось —
  возвращаются на место через finally. На диске после теста ничего не
  должно измениться по сравнению с тем, что было до его запуска.
*/

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const корень = path.join(__dirname, '..');
const файлЗадач = path.join(корень, 'ЗАДАЧИ.md');
const файлРабот = path.join(корень, 'штаб', 'в-работе.json');
const программа = path.join(корень, 'штаб', 'в-работе.js');

const сломать = process.argv.includes('--сломать');

/* Минимальный, но честный ЗАДАЧИ.md: раздел «В работе» между двумя другими
   разделами — так же, как в настоящем файле, чтобы проверить и поиск
   границ раздела, а не только сам текст внутри. */
const тестовыйЗадачиMd =
  '# Задачи проекта (тестовая заготовка)\n\n' +
  '## Раздел до\n\nТекст раздела до.\n\n' +
  '## В работе прямо сейчас\n\n(будет переписано программой)\n\n' +
  '## Раздел после\n\nТекст раздела после.\n';

function работаJson(текст, важность) {
  return JSON.stringify({
    работы: [
      { что: текст, важность: важность || 'скоро', кто: 'developer', начато: '2026-01-01 10:00' }
    ],
    заметка: ''
  }, null, 2) + '\n';
}

function запуститьПрограмму() {
  // Программа сама пишет доп. строку от сторожа простоя — не важна для проверки, просто отдаём вывод.
  return execFileSync(process.execPath, [программа], { cwd: корень, encoding: 'utf8' });
}

/* Сохраняем настоящие файлы, чтобы вернуть их после теста в исходный вид. */
const резервЗадач = fs.existsSync(файлЗадач) ? fs.readFileSync(файлЗадач, 'utf8') : null;
const резервРабот = fs.existsSync(файлРабот) ? fs.readFileSync(файлРабот, 'utf8') : null;

// Общий счётчик проверок и провалов — как в остальных файлах tests/ (см. правило штаб/.claude/rules/проверки.md).
let проверок = 0;
const провалы = [];

function проверить(условие, что) {
  проверок++;
  if (!условие) {
    провалы.push(что);
    console.log('  ПРОВАЛ: ' + что);
  }
}

try {
  if (!сломать) {
    /* --- Обычный прогон: одна и та же работа, несколько вызовов подряд --- */
    fs.writeFileSync(файлЗадач, тестовыйЗадачиMd, 'utf8');
    fs.writeFileSync(файлРабот, работаJson('Тестовая работа №1'), 'utf8');

    // Вызов 1: раздел в ЗАДАЧИ.md ещё пустой — программа обязана его заполнить.
    запуститьПрограмму();
    const послеВызова1 = fs.readFileSync(файлЗадач, 'utf8');
    проверить(
      послеВызова1.includes('Тестовая работа №1'),
      'после первого вызова работа не попала в ЗАДАЧИ.md'
    );

    // Вызов 2: данные те же самые, сразу следом — файл трогать не должно.
    запуститьПрограмму();
    const послеВызова2 = fs.readFileSync(файлЗадач, 'utf8');
    проверить(
      послеВызова2 === послеВызова1,
      'второй вызов подряд с теми же данными переписал файл без причины'
    );

    // Искусственно состариваем строку времени — имитируем, что с записи прошло много часов,
    // хотя список работ не изменился. Именно на этом ломалась старая защита (порог 10 минут).
    const состаренный = послеВызова2.replace(
      /Список переписан [^\n]+/,
      'Список переписан 1 января, 00:01'
    );
    fs.writeFileSync(файлЗадач, состаренный, 'utf8');

    // Вызов 3: те же данные, но «старая» запись по времени — по новым правилам файл всё равно не трогаем.
    запуститьПрограмму();
    const послеВызова3 = fs.readFileSync(файлЗадач, 'utf8');
    проверить(
      послеВызова3 === состаренный,
      'вызов с давней записью, но теми же данными, всё равно переписал файл — старый баг вернулся'
    );
  } else {
    /* --- Ломающий прогон: данные реально меняются между вызовами --- */
    fs.writeFileSync(файлЗадач, тестовыйЗадачиMd, 'utf8');
    fs.writeFileSync(файлРабот, работаJson('Тестовая работа А'), 'utf8');

    запуститьПрограмму();
    const шаг1 = fs.readFileSync(файлЗадач, 'utf8');
    проверить(
      шаг1.includes('Тестовая работа А'),
      'первая запись не прошла, проверять изменения не на чём'
    );

    // Меняем реальные данные: другая работа. Файл обязан перезаписаться.
    fs.writeFileSync(файлРабот, работаJson('Тестовая работа Б'), 'utf8');
    запуститьПрограмму();
    const шаг2 = fs.readFileSync(файлЗадач, 'utf8');
    проверить(
      шаг2.includes('Тестовая работа Б') && шаг2 !== шаг1,
      'работа реально поменялась, а файл остался прежним — защита молчит вечно, это и есть поломка'
    );

    // И ещё раз меняем важность той же работы (важность — часть таблицы, тоже должна замечаться).
    fs.writeFileSync(файлРабот, работаJson('Тестовая работа Б', 'горит'), 'utf8');
    запуститьПрограмму();
    const шаг3 = fs.readFileSync(файлЗадач, 'utf8');
    проверить(
      шаг3 !== шаг2,
      'важность работы поменялась, а таблица в файле — нет'
    );
  }
} finally {
  // Возвращаем боевые файлы штаба на место, что бы ни случилось выше.
  if (резервЗадач !== null) fs.writeFileSync(файлЗадач, резервЗадач, 'utf8');
  if (резервРабот !== null) fs.writeFileSync(файлРабот, резервРабот, 'utf8');
}

console.log('Итого проверок: ' + проверок + ', провалов: ' + провалы.length);
process.exit(провалы.length > 0 ? 1 : 0);
