/* =====================================================================
   ЗОНД ПОЛЁТА КАРТ СОПЕРНИКА — файл тестировщика.

   Живёт В БРАУЗЕРЕ, рядом с настоящей игрой (грузится отдельным тегом
   <script>, ничего в игре не подменяет и не чинит). Ловит РОВНО ТО МЕСТО
   в коде, откуда карта соперника летит на стол: перехватывает
   window.ДвижениеКарт.узел — ту самую дверь, через которую game.js передаёт
   «родину» (узел, откуда начинается прилёт).

   Как отличить свою карту от чужой, не заглядывая в правила игры: у своей
   карты ключ (масть+имя) уже проходил через эту дверь раньше — она видна
   с самого начала в руке. У чужой карты первый раз этот ключ появляется
   ровно в миг, когда она легла на стол (чужие карты в руке идут без масти
   и имени — их игра не знает вовсе). Поэтому «первый раз этот ключ вижу
   вообще» и означает «это чужая карта, только что пришедшая с чьей-то руки».
   Своё мнение о том, кто именно ходил, зонд не имеет — только смотрит,
   какой узел ему передали «родиной».

   Пользоваться (из консоли браузера или через второй <script>):
       window.ЗондПолёта.начать();   // подключиться (один раз на всю страницу)
       window.ЗондПолёта.полёты();   // все карты соперников, что долетели
       window.ЗондПолёта.сброс();    // забыть всё руками (не обязательно:
                                      // подключается и к «новая раздача» сама)
       window.ЗондПолёта.сломать();  // ломающий запуск: подменить get() у
                                      // ктоПоложилКарту, чтобы угадка не работала

   Каждая запись в «полёты»:
       { ключ, времяМС, раздача, родина: { id, класс, номерМеста } }
   «родина.номерМеста» есть только тогда, когда карта прилетела от конкретной
   плашки игрока (dataset.номер). Пусто — значит прилетела из запасной точки
   (полоса #соперники целиком, веер рубашек или колода) — того самого
   поведения «по-старому», которое задумано на случай, если угадать нельзя.
   ===================================================================== */

(function () {
  'use strict';

  /* Ключи, которые сейчас где-то на экране (рука, стол — неважно где):
     то же самое множество, что «использованные» записи внутреннего склада
     движение-карт.js. Обновляется КАЖДЫЙ кадр — см. «конецКадраПометка».

     ПОЧЕМУ НЕЛЬЗЯ ПРОСТО «ВИДЕЛ ХОТЬ РАЗ» (и так было в первой версии зонда).
     Карту можно забрать в руку («Беру») и разыграть заново в той же
     раздаче — тот же ключ (масть+имя) законно появляется на столе ВТОРОЙ раз.
     Настоящий склад в движение-карт.js в этот миг УЖЕ забыл о карте (её
     запись удалена, потому что карта нигде не использовалась целый кадр —
     см. «ушедшие» в конецКадра), и следующее появление там же честно новое.
     Если бы зонд помнил карту вечно, вторую (и все следующие) поставки
     этой же карты он бы принимал за «старую», молча пропуская вылет —
     ровно так и было до этой правки: карта, однажды сыгранная, забранная
     назад и сыгранная снова, переставала засекаться зондом насовсем. */
  var сейчасНаЭкране = new Set();
  var видениеЗаКадр = new Set();      // что видели ИМЕННО в этом кадре — для конца кадра
  var полёты = [];
  var подключено = false;
  var номерРаздачи = 0;

  function описатьУзел(узел) {
    if (!узел) return { нет: true };
    return {
      id: узел.id || null,
      класс: узел.className || null,
      номерМеста: (узел.dataset && узел.dataset.номер) ? String(узел.dataset.номер) : null
    };
  }

  function подключитьДвижение() {
    if (!window.ДвижениеКарт || typeof window.ДвижениеКарт.узел !== 'function') return false;

    var роднойНачалоКадра = window.ДвижениеКарт.началоКадра;
    if (typeof роднойНачалоКадра === 'function') {
      window.ДвижениеКарт.началоКадра = function () {
        видениеЗаКадр.clear();
        return роднойНачалоКадра.apply(this, arguments);
      };
    }

    var роднойУзел = window.ДвижениеКарт.узел;
    window.ДвижениеКарт.узел = function (ключ, создать, настройки) {
      var ужеБыло = ключ ? сейчасНаЭкране.has(ключ) : true;
      if (ключ) { видениеЗаКадр.add(ключ); }
      var результат = роднойУзел(ключ, создать, настройки);
      try {
        if (!ужеБыло && ключ && настройки && настройки.переворот && настройки.долгийЛёт) {
          полёты.push({
            ключ: ключ,
            времяМС: Date.now(),
            раздача: номерРаздачи,
            родина: описатьУзел(настройки.родина)
          });
        }
      } catch (е) { /* зонд не должен ронять игру своей же ошибкой */ }
      return результат;
    };

    var роднойКонецКадра = window.ДвижениеКарт.конецКадра;
    if (typeof роднойКонецКадра === 'function') {
      window.ДвижениеКарт.конецКадра = function () {
        var результат = роднойКонецКадра.apply(this, arguments);
        // Ключи этого кадра — теперь «на экране». Кто в этот кадр не
        // засветился нигде (ни в чьей руке, ни на столе) — тот ушёл
        // (в отбой или в чужую скрытую руку): следующее появление
        // будет для зонда снова новым, как и для настоящего склада.
        сейчасНаЭкране = new Set(видениеЗаКадр);
        return результат;
      };
    }

    var роднаяЗабывалка = window.ДвижениеКарт.забытьВсё;
    if (typeof роднаяЗабывалка === 'function' && !window.ДвижениеКарт.__зондПатчилЗабывалку) {
      window.ДвижениеКарт.забытьВсё = function () {
        сейчасНаЭкране.clear();
        видениеЗаКадр.clear();
        номерРаздачи++;
        return роднаяЗабывалка.apply(this, arguments);
      };
      window.ДвижениеКарт.__зондПатчилЗабывалку = true;
    }
    return true;
  }

  window.ЗондПолёта = {
    начать: function () {
      if (подключено) return 'уже подключён';
      var вышло = подключитьДвижение();
      подключено = вышло;
      return вышло ? 'подключён' : 'window.ДвижениеКарт ещё не готов — попробуйте позже';
    },
    полёты: function () { return полёты.slice(); },
    сброс: function () {
      сейчасНаЭкране.clear(); видениеЗаКадр.clear();
      полёты.length = 0; номерРаздачи = 0;
      return 'сброшено';
    },
    /* Ломающий запуск: без Map угадки любая карта соперника обязана лететь
       из запасной точки. Не покраснело — значит зонд ничего не видит. */
    сломать: function () {
      try {
        var карта = (0, eval)('ктоПоложилКарту');
        if (!карта || typeof карта.get !== 'function') return 'ктоПоложилКарту не найдена';
        карта.get = function () { return undefined; };
        return 'сломано: ктоПоложилКарту.get всегда отдаёт undefined';
      } catch (е) {
        return 'не вышло: ' + е.message;
      }
    }
  };
})();
