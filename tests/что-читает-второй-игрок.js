'use strict';

/* =====================================================================
   Второй игрок за столом, который вслух читает свою ленту.

   ЗАЧЕМ. Рассказ о ходе сервер собирает КАЖДОМУ СВОЙ: «вы добрали 2»
   у одного и «вы добрали 1» у другого — про одно и то же событие.
   Проверить это в браузере нельзя: браузер у проверяющего один.
   Поэтому вторым игроком садится вот этот помощник и печатает всё,
   что видит в своей строке событий, вместе с НОМЕРОМ события.

   Номер — главное: по нему строку помощника кладут рядом со строкой
   из браузера и смотрят, совпадают ли слова и расходятся ли числа.

   Играет он нарочно просто: кроет самой мелкой подходящей картой,
   ходит с мелочи, козыри бережёт. Его дело — не выиграть, а не дать
   столу простаивать.

   Как запускать (сервер комнат уже поднят, комнату создали в браузере):

       node tests/что-читает-второй-игрок.js КОД "Имя" 8790

   Останавливать — Ctrl+C.
   ===================================================================== */

const http = require('http');

const КОД = (process.argv[2] || '').toUpperCase();
const ИМЯ = process.argv[3] || 'Напарник';
const ПОРТ = Number(process.argv[4]) || 8790;
const ХОЗЯИН = '127.0.0.1';

if (!КОД) {
  console.error('Скажите код комнаты: node tests/что-читает-второй-игрок.js КОД "Имя" 8790');
  process.exit(1);
}

function спросить(путь, тело) {
  return new Promise((готово, беда) => {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, (ответ) => {
      let текст = '';
      ответ.setEncoding('utf8');
      ответ.on('data', (к) => { текст += к; });
      ответ.on('end', () => {
        let р = null;
        try { р = JSON.parse(текст); } catch (сбой) { р = { сырое: текст }; }
        готово({ код: ответ.statusCode, тело: р });
      });
    });
    запрос.setTimeout(40000, () => запрос.destroy(new Error('сервер молчит')));
    запрос.on('error', беда);
    запрос.end(данные);
  });
}

const пауза = (мс) => new Promise((r) => setTimeout(r, мс));

let подкидыватьБольшеНеПробуем = false;

function бьёт(чем, что, козырь) {
  if (чем.масть === что.масть) return чем.вес > что.вес;
  return чем.масть === козырь && что.масть !== козырь;
}

/** Что делать в этом положении. Ровно то же простое решение, что у напарника. */
function решить(вид) {
  const рука = вид.мояРука || [];
  const стол = вид.стол || [];
  const козырь = вид.козырь;
  const яЗащищаюсь = вид.яОтбиваюсь === undefined
    ? (вид.фаза === 'защита' && вид.яХожу)
    : вид.яОтбиваюсь;

  if (яЗащищаюсь && !вид.берут && вид.яХожу) {
    let номер = -1;
    for (let i = 0; i < стол.length; i++) { if (!стол[i].защита) { номер = i; break; } }
    if (номер < 0) return null;
    const атака = стол[номер].атака;
    const годные = рука.map((к, i) => ({ к, i }))
      .filter((п) => атака && бьёт(п.к, атака, козырь))
      .sort((а, б) => (а.к.масть === козырь ? 1 : 0) - (б.к.масть === козырь ? 1 : 0) || а.к.вес - б.к.вес);
    if (годные.length) return { действие: 'отбить', пара: номер, карта: годные[0].i };
    return { действие: 'беру' };
  }

  if (вид.яХожу) {
    if (!рука.length) return стол.length ? { действие: 'бито' } : null;
    if (!стол.length) {
      const порядок = рука.map((к, i) => ({ к, i }))
        .sort((а, б) => (а.к.масть === козырь ? 1 : 0) - (б.к.масть === козырь ? 1 : 0) || а.к.вес - б.к.вес);
      return { действие: 'ходить', карта: порядок[0].i };
    }
    if (подкидыватьБольшеНеПробуем) return { действие: 'бито' };
    const веса = new Set();
    стол.forEach((п) => { if (п.атака) веса.add(п.атака.вес); if (п.защита) веса.add(п.защита.вес); });
    const годная = рука.findIndex((к) => веса.has(к.вес) && к.масть !== козырь);
    if (годная >= 0) return { действие: 'ходить', карта: годная };
    return { действие: 'бито' };
  }
  return null;
}

/** Сколько у меня карт в руке — чтобы видеть свой настоящий добор. */
function вРуке(вид) { return (вид.мояРука || []).length; }

async function главная() {
  const вход = await спросить('/войти', { код: КОД, имя: ИМЯ, метка: 'проверка-двух-взглядов' });
  if (вход.код !== 200) {
    console.error('Войти не вышло: ' + вход.код + ' ' + JSON.stringify(вход.тело));
    process.exit(1);
  }
  const пропуск = вход.тело.пропуск;
  console.log('Сел за стол под именем «' + ИМЯ + '», комната ' + КОД);
  console.log('Дальше печатаю каждое событие: номер, слова, сколько у меня карт.');
  console.log('');

  let последнийНомер = -1;
  let былоВРуке = null;
  let тихо = 0;

  for (let шаг = 0; шаг < 20000; шаг++) {
    const с = await спросить('/состояние', { код: КОД, пропуск });
    if (с.код !== 200) { console.log('Комната пропала: ' + с.код); break; }
    const вид = с.тело.состояние || с.тело;

    if (вид.номерСобытия !== последнийНомер) {
      последнийНомер = вид.номерСобытия;
      const стало = вРуке(вид);
      const рост = былоВРуке === null ? '' : ' (в руке было ' + былоВРуке + ', стало ' + стало + ')';
      console.log('  событие №' + вид.номерСобытия + ' [' + (вид.видСобытия || '—') + ']  «' +
                  (вид.событие || '') + '»' + рост);
      былоВРуке = стало;
    }

    if (вид.завершена) {
      console.log('Партия окончена. Итог для меня: ' + вид.итог);
      // Соглашаемся на реванш, чтобы стол не простаивал.
      await спросить('/ход', { код: КОД, пропуск, действие: 'ещё' });
      await пауза(1000);
      continue;
    }

    const намерение = решить(вид);
    if (!намерение) {
      тихо++;
      await пауза(250);
      if (тихо > 2400) { console.log('Долго не мой ход — выхожу'); break; }
      continue;
    }
    тихо = 0;
    const о = await спросить('/ход', Object.assign({ код: КОД, пропуск }, намерение));
    if (о.код === 200 && о.тело && о.тело.принято === false) {
      if (намерение.действие === 'ходить') подкидыватьБольшеНеПробуем = true;
      else console.log('Сервер отказал: ' + о.тело.причина);
    }
    if (намерение.действие === 'бито' || намерение.действие === 'беру') {
      подкидыватьБольшеНеПробуем = false;   // новый подход — пробуем снова
    }
    await пауза(200);
  }
}

главная().catch((беда) => {
  console.error('Сорвалось: ' + беда.message);
  process.exit(1);
});
