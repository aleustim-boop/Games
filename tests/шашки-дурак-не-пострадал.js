/* =====================================================================
   Общий js/telegram.js теперь работает на двоих. Проверяем, что дурак
   ничего не заметил: его рекорды пишутся под свой ключ, шашечные строки
   в его таблицу не попадают, а обе страницы живут в одном хранилище
   (одна память браузера, одно поддельное облако) без единой ошибки.
   ===================================================================== */

const { chromium, подготовитьПодделку, общееОблако } = require('./браузер-робот.js');
const ПОРТ = Number(process.argv[2]) || 8080;    // страничный сервер уже поднят
const ДУРАК = 'http://127.0.0.1:' + ПОРТ + '/index.html';
const ШАШКИ = 'http://127.0.0.1:' + ПОРТ + '/шашки.html';

let провалов = 0;
function проверить(условие, слова) {
  console.log((условие ? '  ок   — ' : '  ПЛОХО— ') + слова);
  if (!условие) провалов++;
}

/* Поддельное облако — ОДНО на обе страницы: живёт в памяти процесса
   проверки, а не страницы; общая подделка ходит в него через мостик. */
const облако = общееОблако();

async function подготовить(страница, ошибки) {
  страница.on('pageerror', (о) => ошибки.push('исключение: ' + о.message));
  страница.on('console', (с) => {
    if (с.type() === 'error' && /Failed to load resource/.test(с.text())) return;
    if (с.type() === 'error') ошибки.push('консоль: ' + с.text());
  });
  await подготовитьПодделку(страница, { версия: '7.0', общееОблако: облако });
}

(async () => {
  const браузер = await chromium.launch();
  const окно = await браузер.newContext({ viewport: { width: 390, height: 844 } });
  const страница = await окно.newPage();
  const ошибки = [];
  await подготовить(страница, ошибки);

  console.log('\n=== 1. Дурак записывает свой рекорд по-старому, без слова «игра» ===');
  await страница.goto(ДУРАК);
  await страница.waitForTimeout(500);
  const дурак1 = await страница.evaluate(async () => {
    const после = await window.saveScore(2, 'сложный');   // как зовёт game.js: два довода
    const своя = await window.loadScore();
    const чужая = await window.loadScore('шашки');
    return { лучший: после.лучший, строк: своя.таблица.length, шашечных: чужая.таблица.length };
  });
  проверить(дурак1.лучший === 2 && дурак1.строк === 1, 'дурак записал «2 подряд» и видит одну строку');
  проверить(дурак1.шашечных === 0, 'таблица шашек с той же страницы пуста: ' + дурак1.шашечных);
  проверить('records_durak' in облако && !('records_shashki' in облако),
    'в облаке только records_durak: ' + Object.keys(облако).join(', '));

  console.log('\n=== 2. Шашки пишут рядом, в свой ключ ===');
  await страница.goto(ШАШКИ);
  await страница.waitForTimeout(500);
  const шашки = await страница.evaluate(async () => {
    const подписи = [];
    for (const шаг of [['победа', 'лёгкий'], ['победа', 'лёгкий'], ['победа', 'обычный']]) {
      подписи.push(await window.ШашкиРекорды.записатьПартию({ исход: шаг[0], уровень: шаг[1] }));
    }
    const своя = await window.loadScore('шашки');
    const дуракова = await window.loadScore();
    return { подписи, своя: своя.таблица.map((с) => с.очки + ' ' + с.сложность), дураковых: дуракова.таблица.length };
  });
  console.log('  подписи: ' + шашки.подписи.join(' | '));
  console.log('  таблица шашек: ' + шашки.своя.join(' | '));
  проверить(шашки.своя.length === 1 && шашки.своя[0] === '3 лёгкий',
    'три победы на двух уровнях — одна строка, подписана самым лёгким уровнем');
  проверить(шашки.дураковых === 1, 'дуракова таблица со страницы шашек по-прежнему одна строка');
  проверить('records_shashki' in облако && 'rating_shashki' in облако, 'в облаке появились records_shashki и rating_shashki');

  console.log('\n=== 3. Дурак после этого показывает только своё ===');
  await страница.goto(ДУРАК);
  await страница.waitForTimeout(500);
  // Первым экраном теперь витрина «Настольные игры»: сначала выбираем «Дурак».
  // Стенд писался до витрины и упирался в скрытую кнопку — не в игру.
  if (await страница.locator('#экран-витрины').isVisible()) {
    await страница.click('#экран-витрины button:has-text("Дурак")');
    await страница.waitForTimeout(200);
  }
  // «Рекорды» у дурака лежат на экране игры с ботом, а не в первом меню
  /* Ждём саму кнопку, а не «двести миллисекунд»: на занятой машине экран
     успевает не всегда, и проверка срывалась на ровном месте. */
  await страница.click('#кнопка-режим-бот');
  await страница.waitForSelector('#кнопка-рекорды', { state: 'visible', timeout: 10000 });
  await страница.click('#кнопка-рекорды');
  await страница.waitForTimeout(700);   // хранилище отвечает через поддельное облако
  const дурак2 = await страница.evaluate(() => {
    const строки = Array.from(document.querySelectorAll('#таблица-рекордов .таблица__строка'));
    return строки.map((с) => Array.from(с.children).map((я) => я.textContent).filter(Boolean).join(' | '));
  });
  console.log('  экран рекордов дурака: ' + (дурак2.join(' || ') || 'пусто'));
  проверить(дурак2.length === 1 && /2 победы подряд/.test(дурак2[0]) && /сложный/.test(дурак2[0]),
    'у дурака одна строка — его собственная «2 победы подряд · сложный»');
  проверить(!дурак2.some((с) => /лёгкий/.test(с)), 'шашечной строки «3 · лёгкий» у дурака нет');
  проверить(JSON.parse(облако.records_durak).таблица.length === 1, 'запись дурака в облаке не выросла от шашек');

  проверить(ошибки.length === 0, 'красных ошибок ни на одной странице' + (ошибки.length ? ': ' + ошибки.join(' | ') : ''));
  await браузер.close();
  console.log('\n' + (провалов === 0 ? 'ВСЁ ЗЕЛЁНОЕ' : 'ПРОВАЛОВ: ' + провалов));
  process.exit(провалов === 0 ? 0 : 1);
})().catch((о) => { console.error('проверка сломалась:', о); process.exit(2); });
