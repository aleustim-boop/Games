const fs = require('fs');
const path = require('path');
const http = require('http');

const ПРОЕКТ = path.join(__dirname, '..');
const { chromium, подготовитьПодделку } = require(path.join(ПРОЕКТ, 'tests', 'браузер-робот.js'));

const ПОРОГ_ОБЫЧНЫЙ_МС = 9000;
const ПОРОГ_МЕДЛЕННЫЙ_МС = 12000;
const ЖДАТЬ_КОНЦА_МС = 50000;
const ПАРТИЙ_НА_РЕЖИМ = 3;
const НУЖНО_ТИХИХ = 0;   // боты бьются в каждом раунде: тихий раунд не встречается (расписание в js/захват-раскрытие.js одно на все раунды, ФАЗЫ)
const РАУНДОВ_В_ПАРТИИ = 3;

let провалов = 0;
let проверок = 0;
function проверить(условие, слова) {
  проверок++;
  console.log((условие ? '  ок   — ' : '  ПЛОХО— ') + слова);
  if (!условие) провалов++;
  return условие;
}

const ТИПЫ = {
  '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8', '.json': 'application/json',
  '.svg': 'image/svg+xml', '.webp': 'image/webp', '.png': 'image/png',
  '.jpg': 'image/jpeg', '.woff2': 'font/woff2', '.woff': 'font/woff', '.ttf': 'font/ttf'
};

/* Сервер: сперва ищет файл в папке-копии (если дана), потом в проекте. */
function поднятьСервер(копия) {
  const сервер = http.createServer((запрос, ответ) => {
    let путь = '/';
    try { путь = decodeURIComponent(запрос.url.split('?')[0]); } catch (_) { /* как есть */ }
    if (путь === '/') путь = '/index.html';
    const варианты = [];
    if (копия) варианты.push([копия, path.join(копия, путь)]);
    варианты.push([ПРОЕКТ, path.join(ПРОЕКТ, путь)]);
    for (const [корень, файл] of варианты) {
      if (!файл.startsWith(корень)) continue;
      try {
        if (fs.statSync(файл).isFile()) {
          ответ.writeHead(200, { 'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'application/octet-stream' });
          ответ.end(fs.readFileSync(файл));
          return;
        }
      } catch (_) { /* пробуем дальше */ }
    }
    ответ.writeHead(404); ответ.end('нет такого файла');
  });
  return new Promise(готово => сервер.listen(0, '127.0.0.1', () => готово(сервер)));
}

/* Порча: КОПИЯ js/захват-экран.js в данной папке, где конец раскрытия и все шаги растянуты до 30 000 мс. */
function испортитьКопию(папка) {
  const корень = path.resolve(ПРОЕКТ) + path.sep;
  if ((path.resolve(папка) + path.sep).startsWith(корень)) {
    throw new Error('--сломать: папка копии лежит внутри проекта; нужна временная папка вне проекта');
  }
  const исходник = fs.readFileSync(path.join(ПРОЕКТ, 'js', 'захват-экран.js'), 'utf8');
  const шагиБыло = 'setTimeout(() => сделатьШаг(шаг), шаг.с)';
  const конецБыло = 'setTimeout(закончитьРаскрытие, расписание.всегоМс)';
  if (исходник.split(шагиБыло).length !== 2 || исходник.split(конецБыло).length !== 2) {
    throw new Error('--сломать: в js/захват-экран.js не нашлись таймеры расписания раскрытия (якорь не найден — провал)');
  }
  const порченый = исходник
    .replace(шагиБыло, () => 'setTimeout(() => сделатьШаг(шаг), шаг.с * 30000 / Math.max(1, расписание.всегоМс))')
    .replace(конецБыло, () => 'setTimeout(закончитьРаскрытие, 30000)');
  fs.mkdirSync(path.join(папка, 'js'), { recursive: true });
  fs.writeFileSync(path.join(папка, 'js', 'захват-экран.js'), порченый);
}

const аргументы = process.argv.slice(2);
const индексПорчи = аргументы.indexOf('--сломать');
const ЛОМАЮ = индексПорчи !== -1;
let копия = null;
if (ЛОМАЮ) {
  копия = аргументы[индексПорчи + 1];
  if (!копия || /^--/.test(копия)) {
    console.error('Укажите путь к временной папке копии: --сломать <путь>');
    process.exit(2);
  }
  копия = path.resolve(копия);
  испортитьКопию(копия);
}

/* Новая страница: подделка Telegram, «не новичок», слушатели ошибок, счётчик «вспышек» боёв на холсте. */
async function открыть(браузер, порт) {
  const контекст = await браузер.newContext({ viewport: { width: 390, height: 844 } });
  const страница = await контекст.newPage();
  await подготовитьПодделку(страница, {});
  const ошибки = [];
  страница.on('console', с => {
    const адрес = с.location().url || '';
    if (с.type() === 'error' && адрес.indexOf('telegram-web-app.js') === -1) ошибки.push(с.text() + ' ' + адрес);
  });
  страница.on('pageerror', е => ошибки.push('необработанная ошибка: ' + е.message));
  await страница.addInitScript(() => {
    try { localStorage.setItem('zahvat-learned', '1'); } catch (_) { /* пусто */ }
    // Вспышка — это бой. Считаем рисунки листа вспышки на холсте.
    window.__вспышек = 0;
    const ориг = CanvasRenderingContext2D.prototype.drawImage;
    CanvasRenderingContext2D.prototype.drawImage = function (img) {
      try {
        if (img && img.src && /вспышка-кадры/.test(decodeURIComponent(img.src))) window.__вспышек++;
      } catch (_) { /* пусто */ }
      return ориг.apply(this, arguments);
    };
  });
  await страница.goto('http://127.0.0.1:' + порт + '/захват.html', { waitUntil: 'load' });
  await страница.waitForTimeout(800);
  return { контекст, страница, ошибки };
}

/* Один раунд: «Готово» → ждём конец раскрытия. Ответ: { мс, бои } или { мс: null }. */
async function сыгратьРаунд(страница) {
  await страница.evaluate(() => {
    window.__т0 = performance.now(); window.__начало = null; window.__т1 = null; window.__вспышекДо = window.__вспышек;
    const готово = document.getElementById('захват-готово');
    if (!window.__наблюдатель) {
      window.__наблюдатель = new MutationObserver(() => {
        if (window.__т1 !== null) return;
        const заперта = готово.hasAttribute('disabled');
        if (заперта && window.__начало === null) window.__начало = performance.now();
        else if (!заперта && window.__начало !== null) window.__т1 = performance.now();
      });
      window.__наблюдатель.observe(готово, { attributes: true, attributeFilter: ['disabled'] });
      document.addEventListener('click', е => {
        if (е.target.closest && е.target.closest('#захват-готово, #захват-остаток-да') && window.__т1 === null) window.__т0 = performance.now();
      }, true);
    }
  });
  await страница.click('#захват-готово');
  if (await страница.evaluate(() => { const у = document.getElementById('захват-остаток'); return !!у && !у.classList.contains('скрыт'); })) {
    await страница.click('#захват-остаток-да', { timeout: 4000 }).catch(() => {});
  }
  const дошло = await страница.waitForFunction(() => window.__т1 !== null, null, { timeout: ЖДАТЬ_КОНЦА_МС, polling: 100 }).then(() => true, () => false);
  const р = await страница.evaluate(() => ({ т0: window.__т0, т1: window.__т1, начало: window.__начало, бои: window.__вспышек - window.__вспышекДо }));
  if (!дошло || р.т1 === null) return { мс: null, бои: р.бои, началось: р.начало !== null };
  return { мс: Math.round(р.т1 - р.т0), бои: р.бои, началось: true };
}

const кнопкаВключена = страница => страница.evaluate(() => { const к = document.getElementById('захват-готово'); return !!к && !к.hasAttribute('disabled'); });

/* Режим: ПАРТИЙ_НА_РЕЖИМ партий; в каждой первый раунд и далее тихие, пока их не хватит. */
async function замерРежима(браузер, порт, имя, замедление) {
  const строки = [];   // { партия, раунд, вид: 'первый' | 'тихий' | 'с боями', мс }
  const сбои = [];
  const ошибкиВсе = [];
  const партий = ЛОМАЮ ? 1 : ПАРТИЙ_НА_РЕЖИМ;
  for (let п = 1; п <= партий; п++) {
    const { контекст, страница, ошибки } = await открыть(браузер, порт);
    try {
      if (замедление > 1) {
        const сессия = await контекст.newCDPSession(страница);
        await сессия.send('Emulation.setCPUThrottlingRate', { rate: замедление });
      }
      await страница.click('#захват-боты');
      await страница.waitForTimeout(300);
      await страница.click('#захват-выбор-число [data-значение="3"]');
      await страница.click('#захват-начать');
      await страница.waitForTimeout(1500);
      for (let р = 1; р <= РАУНДОВ_В_ПАРТИИ; р++) {
                if (р > 1 && ЛОМАЮ) break;
        if (!(await кнопкаВключена(страница))) { сбои.push(имя + ', партия ' + п + ', раунд ' + р + ': стол не принимает расстановку (кнопка «Готово» заперта)'); break; }
        const з = await сыгратьРаунд(страница);
        if (з.мс === null) {
          сбои.push(имя + ', партия ' + п + ', раунд ' + р + ': конец раскрытия не наступил за ' + ЖДАТЬ_КОНЦА_МС / 1000 + ' с' + (з.началось ? '' : ' (раскрытие даже не началось)'));
          break;
        }
        const вид = р === 1 ? 'первый' : (з.бои > 0 ? 'с боями' : 'тихий');
        строки.push({ партия: п, раунд: р, вид, бои: з.бои, мс: з.мс });
        console.log('    ' + имя + ': партия ' + п + ', раунд ' + р + ' (' + вид + ', кадров боя ' + з.бои + '): ' + з.мс + ' мс');
        await страница.waitForTimeout(400);
      }
    } catch (е) {
      сбои.push(имя + ', партия ' + п + ': замер упал: ' + String(е.message || е).split('\n')[0]);
    }
    ошибкиВсе.push(...ошибки);
    await контекст.close();
  }
  return { строки, сбои, ошибки: ошибкиВсе };
}

const сек = мс => (мс / 1000).toFixed(1).replace('.', ',') + ' с';

async function главная() {
  const сервер = await поднятьСервер(копия);
  const порт = сервер.address().port;
  console.log('Сервер проверки: порт ' + порт + ', PID ' + process.pid + (копия ? ', КОПИЯ с растянутым раскрытием: ' + копия : ''));
  const браузер = await chromium.launch();
  const итоги = [];
  try {
    for (const [имя, замедление, порог] of [['обычный режим', 1, ПОРОГ_ОБЫЧНЫЙ_МС], ['процессор ×4 медленнее', 4, ПОРОГ_МЕДЛЕННЫЙ_МС]]) {
      console.log('\n=== ' + имя + ' (порог ' + сек(порог) + ') ===');
      итоги.push({ имя, порог, р: await замерРежима(браузер, порт, имя, замедление) });
    }
  } finally {
    await браузер.close();
    сервер.close();
  }

  console.log('\n=== Итоги ===');
  for (const { имя, порог, р } of итоги) {
    console.log('\n' + имя + ':');
    for (const вид of ['первый', 'тихий', 'с боями']) {
      const м = р.строки.filter(с => с.вид === вид).map(с => с.мс);
      console.log('  ' + (вид + '        ').slice(0, 8) + ': ' + (м.length ? м.map(сек).join(', ') + '  (худший ' + сек(Math.max.apply(null, м)) + ')' : 'замеров нет'));
    }
    const доПорога = р.строки;   // порог — на ВСЕ замеры, и на тихие, и на раунды с боями
    проверить(р.строки.length > 0, имя + ': хоть раз удалось дождаться конца раскрытия (замеров ' + р.строки.length + '; ноль — провал)');
    проверить(!р.сбои.length, имя + ': ни один замер не оборвался' + (р.сбои.length ? ': ' + р.сбои.join(' | ') : ''));
    проверить(ЛОМАЮ || р.строки.filter(с => с.вид === 'первый').length >= ПАРТИЙ_НА_РЕЖИМ, имя + ': первых раундов замерено ' + р.строки.filter(с => с.вид === 'первый').length + ' из ' + ПАРТИЙ_НА_РЕЖИМ);
    console.log('  справка: тихих раундов (без боёв) встретилось ' + р.строки.filter(с => с.вид === 'тихий').length + '; у ботов бой в каждом раунде');
    const долгие = доПорога.filter(с => с.мс > порог);
    проверить(доПорога.length > 0 && !долгие.length, имя + ': все замеренные раунды не длиннее ' + сек(порог)
      + (долгие.length ? '; дольше порога: ' + долгие.map(с => 'партия ' + с.партия + ' раунд ' + с.раунд + ' (' + с.вид + ') ' + сек(с.мс)).join(', ') : ''));
    проверить(!р.ошибки.length, имя + ': консоль без ошибок' + (р.ошибки.length ? ': ' + р.ошибки.slice(0, 3).join(' | ') : ''));
  }
  console.log('\nИтого проверок: ' + проверок + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
}

главная().catch(е => { console.error('Проверка упала: ' + (е && е.stack || е)); process.exit(2); });
