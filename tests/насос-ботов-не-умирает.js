/** Число из строчки вида «const ИМЯ = 3 * 1000;» в чужом файле. */
function числоИзКода(файл, имя) {
  let текст = '';
  try { текст = fs.readFileSync(файл, 'utf8'); } catch (сбой) { return null; }
  const найдено = new RegExp('const\\s+' + имя + '\\s*=\\s*([^;]+);').exec(текст);
  if (!найдено) return null;
  const выражение = найдено[1].trim();
  if (!/^[\d\s+\-*/().]+$/.test(выражение)) return null;      // только простая арифметика
  try {
    const число = Function('"use strict"; return (' + выражение + ');')();
    return Number.isFinite(число) ? число : null;
  } catch (сбой) { return null; }
}

const ПАУЗА_БОТА = Number(партии.ПАУЗА_БОТА) || 700;
const УБОРКА_КАЖДЫЕ = числоИзКода(path.join(КОРЕНЬ, 'server', 'комнаты.js'), 'УБОРКА_КАЖДЫЕ') || 3000;

/* Сколько ждём, прежде чем сказать «стол мёртв».
   Считаем не от балды: сервер сам обещает поднять уснувший насос
   ближайшей уборкой («сторож насоса ботов» в server/комнаты.js).
   Даём ему четыре уборки подряд и, отдельно, двадцать ходов бота —
   что длиннее. Ждать дольше незачем: человек за экраном ждёт меньше. */
const ТЕРПЕНИЕ = Math.max(4 * УБОРКА_КАЖДЫЕ, 20 * ПАУЗА_БОТА);

/* ---------------------------------------------------------------------
   Разговор с сервером — обычными запросами, как из браузера
   --------------------------------------------------------------------- */

function спросить(путь, тело) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело === undefined ? {} : тело), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН_АДРЕС, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (ч) { текст += ч; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (е) { разобрано = { сырое: текст }; }
        готово({ код: ответ.statusCode, тело: разобрано });
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

/** Простой запрос без тела — им спрашивают «сервер, ты живой?». */
function спроситьПросто(путь) {
  return new Promise(function (готово) {
    http.get({ host: ХОЗЯИН_АДРЕС, port: ПОРТ, path: encodeURI(путь) }, function (ответ) {
      let текст = '';
      ответ.on('data', function (ч) { текст += ч; });
      ответ.on('end', function () {
        try { готово(JSON.parse(текст || '{}')); } catch (е) { готово({ сырое: текст }); }
      });
    }).on('error', function (сбой) { готово({ сырое: 'связи нет: ' + сбой.code }); });
  });
}

/** Собрать стол: комната, боты на все места кроме моего, «Начать». */
async function собратьСтол() {
  const создано = await спросить('/создать', { игроки: МЕСТ });
  if (!создано.тело || !создано.тело.код) {
    throw new Error('комнату создать не вышло: ' + JSON.stringify(создано.тело));
  }
  const стол = { код: создано.тело.код, пропуск: создано.тело.пропуск };
  for (let i = 0; i < МЕСТ - 1; i++) {
    await спросить('/ход', { код: стол.код, пропуск: стол.пропуск, действие: 'бот' });
  }
  await спросить('/ход', { код: стол.код, пропуск: стол.пропуск, действие: 'начать' });
  return стол;
}

async function состояние(стол) {
  const о = await спросить('/состояние', { код: стол.код, пропуск: стол.пропуск });
  return (о.тело && о.тело.состояние) || {};
}

async function походить(стол, намерение) {
  const тело = Object.assign({ код: стол.код, пропуск: стол.пропуск }, намерение);
  const о = await спросить('/ход', тело);
  return о.тело || {};
}

/* ---------------------------------------------------------------------
   Законный ход человека — считаем правилами игры, а не наугад

   Наугад нельзя нарочно: перебор «а вдруг эта карта ляжет» — это поток
   отказных ходов, то есть ровно то, что проверка изучает. Тихий стол
   обязан быть по-настоящему тихим, иначе первая часть проверки
   измеряла бы то же самое, что вторая.
   --------------------------------------------------------------------- */

function законныйХод(вид) {
  const рука = вид.мояРука || [];
  const стол = вид.стол || [];

  if (вид.фаза === 'защита') {
    for (let пара = 0; пара < стол.length; пара++) {
      if (стол[пара].защита) continue;                    // эта уже отбита
      for (let к = 0; к < рука.length; к++) {
        if (правила.бьёт(рука[к], стол[пара].атака, вид.козырь)) {
          return { действие: 'отбить', карта: к, пара: пара };
        }
      }
    }
    return { действие: 'беру' };
  }

  if (вид.фаза === 'атака') return { действие: 'ходить', карта: 0 };

  // Подкидывание и докидывание: класть можно только достоинством со стола.
  if (вид.могуПодкинуть) {
    const достоинства = правила.достоинстваНаСтоле({ стол: стол });
    for (let к = 0; к < рука.length; к++) {
      if (достоинства.indexOf(рука[к].имя) !== -1) return { действие: 'ходить', карта: к };
    }
  }
  return { действие: 'бито' };
}

/* Отпечаток стола: по нему видно, сдвинулось хоть что-нибудь или нет. */
function отпечаток(вид) {
  return JSON.stringify([вид.версия, вид.фаза, (вид.стол || []).length, (вид.мояРука || []).length]);
}

function ктоХодитИмя(вид) {
  const место = ((вид.застолом || []).filter(function (м) { return м.ходит; })[0]) || null;
  return место ? место.имя + (место.этоБот ? ' (бот)' : ' (человек)') : 'никто';
}

/* ---------------------------------------------------------------------
   Часть 1. Тихий стол: партия с ботами доигрывается до конца

   Это опорная точка. Провалится она — значит, дело не в тыкании вовсе,
   и вторую часть читать бессмысленно.
   --------------------------------------------------------------------- */

async function частьТихийСтол() {
  console.log('1. Тихий стол: человек ходит только законно');
  const стол = await собратьСтол();

  let последний = '';
  let замерло = 0;                    // сколько миллисекунд стол не двигается
  let шагов = 0;
  let кончилась = false;

  while (шагов++ < ПОТОЛОК_ШАГОВ) {
    const вид = await состояние(стол);
    if (вид.завершена || вид.этап === 'конец') { кончилась = true; break; }

    const сейчас = отпечаток(вид);
    if (сейчас === последний) замерло += 100; else { замерло = 0; последний = сейчас; }
    if (замерло > замер.самыйДолгийЗастой) замер.самыйДолгийЗастой = замерло;
    if (замерло > ТЕРПЕНИЕ) {
      проверить(false, 'тихий стол встал: ' + Math.round(замерло / 1000) + ' с ничего не происходит, ' +
        'ходить очередь «' + ктоХодитИмя(вид) + '», фаза «' + вид.фаза + '». ' +
        'Человек при этом не сделал ни одного лишнего нажатия');
      break;
    }

    if (вид.яХожу) {
      const ответ = await походить(стол, законныйХод(вид));
      if (!ответ.принято) {
        /* Законный по правилам ход сервер не принял — это уже другая беда,
           но молчать о ней нельзя: она тоже кончается зависанием. */
        проверить(false, 'сервер отклонил ход, который правила считают законным: «' +
          (ответ.причина || 'без причины') + '», фаза «' + вид.фаза + '»');
        break;
      }
    } else {
      await спать(100);
    }
  }

  if (кончилась) замер.партийТихих++;
  проверить(кончилась, 'партия с ботами не доигралась до конца за ' + ПОТОЛОК_ШАГОВ + ' шагов');
  console.log('   партия ' + (кончилась ? 'доиграна' : 'НЕ доиграна') +
              ', самый долгий застой: ' + замер.самыйДолгийЗастой + ' мс' +
              ' (терпение ' + ТЕРПЕНИЕ + ' мс)');
  await спросить('/выйти', { код: стол.код, пропуск: стол.пропуск });
}

/* ---------------------------------------------------------------------
   Часть 2. Нетерпеливый палец: тычем, пока думает бот

   Человек за столом ждёт бота и от нетерпения жмёт кнопку. Сервер
   такой ход отклоняет — и правильно делает. Но отклонить мало:
   боты обязаны ходить дальше, как будто нажатия не было.
   --------------------------------------------------------------------- */

async function частьНетерпеливыйПалец() {
  console.log('2. Нетерпеливый палец: тычем в кнопку, пока ходит бот');
  const стол = await собратьСтол();

  /* Тычем чаще, чем бот успевает подумать, — иначе проверка ничего
     не проверит. Число берём от паузы бота, а не выдумываем. */
  const МЕЖДУ_ТЫЧКАМИ = Math.max(50, Math.floor(ПАУЗА_БОТА / 3));

  let последний = '';
  let замерло = 0;
  let ходовБота = 0;
  let застойПодТыканьем = 0;
  let встал = false;

  const началось = Date.now();
  while (Date.now() - началось < ТЕРПЕНИЕ * 3 && ходовБота < ХОДОВ_БОТА_ДЛЯ_УВЕРЕННОСТИ) {
    const вид = await состояние(стол);
    if (вид.завершена || вид.этап === 'конец') break;

    const сейчас = отпечаток(вид);
    if (сейчас === последний) {
      замерло += МЕЖДУ_ТЫЧКАМИ;
    } else {
      if (последний !== '' && !вид.яХожу) ходовБота++;
      замерло = 0;
      последний = сейчас;
    }
    if (замерло > застойПодТыканьем) застойПодТыканьем = замерло;

    if (замерло > ТЕРПЕНИЕ) {
      встал = true;
      проверить(false, 'СТОЛ ВСТАЛ ОТ НАЖАТИЙ: ' + Math.round(замерло / 1000) +
        ' с ничего не происходит, ходить очередь «' + ктоХодитИмя(вид) + '», фаза «' + вид.фаза + '». ' +
        'Человек всё это время присылал ходы, которые сервер отклоняет (послано ' +
        замер.отказовПослано + ', отклонено ' + замер.отказовПодтверждено + '). ' +
        'Каждый отклонённый ход заново заводит будильник бота (ботыДумают в server/комнаты.js ' +
        'сначала гасит прежний), а бот думает ' + ПАУЗА_БОТА + ' мс — значит, нажатия чаще ' +
        'этого срока не дают ему сходить никогда');
      break;
    }

    if (вид.яХожу) {
      const ответ = await походить(стол, законныйХод(вид));
      if (!ответ.принято) {
        проверить(false, 'сервер отклонил законный ход человека: «' + (ответ.причина || 'без причины') + '»');
        break;
      }
    } else {
      // Не наша очередь — вот тут и тычем.
      замер.отказовПослано++;
      const ответ = await походить(стол, { действие: 'бито' });
      if (ответ.принято === false) замер.отказовПодтверждено++;
      await спать(МЕЖДУ_ТЫЧКАМИ);
    }
  }

  замер.ходовБотаПодТыканьем = ходовБота;
  /* Отдельная проверка на случай, если стол formально не «встал», а просто
     всё это время еле полз: боты обязаны были сходить хоть сколько-то раз. */
  if (!встал) {
    проверить(ходовБота > 0,
      'стол вроде бы шевелился, но боты под нажатиями не сходили ни разу за ' +
      Math.round(ТЕРПЕНИЕ * 3 / 1000) + ' с');
  }
  console.log('   ходов бота под тыканьем: ' + ходовБота + ' из ' + ХОДОВ_БОТА_ДЛЯ_УВЕРЕННОСТИ +
              ', отказных нажатий послано: ' + замер.отказовПослано +
              ', самый долгий застой: ' + застойПодТыканьем + ' мс (терпение ' + ТЕРПЕНИЕ + ' мс)');

  /* -------------------------------------------------------------------
     Часть 3. Палец убрали — стол обязан ожить.

     Разница между «встал навсегда» и «стоит, пока тычут» важна штабу:
     первое чинят немедленно, второе — тоже, но иначе.
     ------------------------------------------------------------------- */
  console.log('3. Палец убрали: оживает ли стол сам');
  const доОтдыха = отпечаток(await состояние(стол));
  let ожил = false;
  const ждём = Date.now();
  while (Date.now() - ждём < ТЕРПЕНИЕ) {
    await спать(200);
    const вид = await состояние(стол);
    if (вид.завершена || вид.этап === 'конец' || отпечаток(вид) !== доОтдыха) { ожил = true; break; }
  }
  проверить(ожил, 'после того как человек перестал нажимать, стол так и не сдвинулся за ' +
    Math.round(ТЕРПЕНИЕ / 1000) + ' с — насос ботов умер совсем');
  console.log('   стол ' + (ожил ? 'ожил за ' + (Date.now() - ждём) + ' мс' : 'НЕ ожил'));

  await спросить('/выйти', { код: стол.код, пропуск: стол.пропуск });
}

