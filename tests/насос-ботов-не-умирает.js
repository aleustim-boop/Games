/* =====================================================================
   НАСОС БОТОВ НЕ УМИРАЕТ.

   ЧТО ТАКОЕ «НАСОС БОТОВ». За сетевым столом боты ходят не в браузере,
   а на самом сервере: комната заводит будильник и через семь десятых
   секунды ходит за бота. Этот будильник в коде и зовут насосом
   (см. «ботыДумают» в server/комнаты.js). Умер насос — за столом
   не сходит никто и никогда: человек смотрит на надпись «ходит Бот 3»
   и не может сделать ровным счётом ничего.

   ЗАЧЕМ ЭТА ПРОВЕРКА. Такая дыра у нас уже была, и её чинили. Починка
   такая: даже ОТКЛОНЁННЫЙ ход заканчивается перезаводом насоса — чтобы
   комната не осталась без будильника. Проверка сторожит именно это
   место, потому что перезавод — палка о двух концах: он сначала гасит
   прежний будильник и только потом заводит новый. Значит, тот, кто
   присылает отказные ходы чаще, чем бот успевает подумать, может
   гасить будильник вечно.

   ЧТО ИМЕННО ПРОВЕРЯЕТСЯ — три вещи, по нарастанию злобы:

     1. ТИХИЙ СТОЛ. Человек и три бота, человек ходит только законно.
        Партия обязана доиграться до конца.
     2. НЕТЕРПЕЛИВЫЙ ПАЛЕЦ. То же самое, но пока думает бот, человек
        тычет в кнопку — присылает ход, который сервер отклоняет.
        Боты обязаны продолжать ходить.
     3. ПОСЛЕ ТЫКАНИЯ. Палец убрали — стол обязан ожить сам.

   ОТКУДА БЕРУТСЯ ЧИСЛА. Своего пересказа правил здесь нет ни одного:
     • сколько думает бот — спрашиваем у сервера (партии.ПАУЗА_БОТА);
     • как часто прибирается уборщик со сторожем насоса — вычитываем
       прямо из server/комнаты.js;
     • какой ход законен — считаем правилами из js/game.js, а не своей
       догадкой.
   Поменяют паузу бота — проверка узнает сама.

   Запуск (свой сервер поднимается сам, рабочий 8790 не трогаем):
       node tests/насос-ботов-не-умирает.js
       node tests/насос-ботов-не-умирает.js 8797      (свой порт)
       node tests/насос-ботов-не-умирает.js 8797 6    (и мест за столом)

   Выход 0 — всё хорошо, 1 — есть провалы.
   ===================================================================== */

