'use strict';
/* Проверка: общая панель «Сказать» (js/деберц-сказать.js) берёт каталог фраз игры.
   Без второго довода — каталог деберца (как раньше); с ЗахватЗнаки — каталог «Захвата».
   Запуск: node tests/сказать-каталог.js
   Ломающий запуск: node tests/сказать-каталог.js --сломать
     — портит КОПИЮ панели во временной папке (второй довод не берётся); проверка (2) обязана покраснеть,
       выход с кодом 1.
   Ломающий запуск цели: node tests/сказать-каталог.js --сломать-цель
     — копия панели, где нужнаЦель не спрашивается: «Мир?» уходит без адресата, (4) обязана покраснеть.
   Пункты (4)–(6): адресат у фразы одному. Пока в ЗахватЗнаки нет нужнаЦель (Б3ф), проверка подкладывает свою.
   Числа и тексты читаются из самих js/деберц-знаки.js и js/захват-знаки.js, не вписаны сюда. */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { сделатьДокумент, поднять } = require('./поддельный-браузер.js');

const КОРЕНЬ = path.join(__dirname, '..');
const ПУТЬ_ПАНЕЛИ = path.join(КОРЕНЬ, 'js', 'деберц-сказать.js');
const ПУТЬ_ДЕБЕРЦ = path.join(КОРЕНЬ, 'js', 'деберц-знаки.js');
const ПУТЬ_ЗАХВАТ = path.join(КОРЕНЬ, 'js', 'захват-знаки.js');
const ДеберцЗнаки = require(ПУТЬ_ДЕБЕРЦ);
const ЗахватЗнаки = require(ПУТЬ_ЗАХВАТ);

const сломать = process.argv.includes('--сломать');
const сломатьЦель = process.argv.includes('--сломать-цель');
const доводПути = process.argv.find(а => а.startsWith('--панель='));

let проверок = 0, провалов = 0;
function надо(условие, что, подробность) {
  проверок++;
  if (!условие) { провалов++; console.log('ПРОВАЛ: ' + что + (подробность ? ' — ' + подробность : '')); }
  else console.log('ок: ' + что);
}

/* Поднимает панель в поддельном браузере. сДоводом — передавать ли ей каталог «Захвата».
   Возвращает вкладки, ряд кнопок и журнал номеров, ушедших «в сеть». */
const ДВА_СОПЕРНИКА = [{ id: 'цель-1', имя: 'Маша', индекс: 1 }, { id: 'цель-2', имя: 'Коля', индекс: 2 }];
const ОДИН_СОПЕРНИК = [{ id: 'цель-1', имя: 'Соперник', индекс: 1 }];

function собрать(путьПанели, сДоводом, игроки) {
  const документ = сделатьДокумент();
  // У поддельного узла нет окон-диалогов — добавляем минимум, как в браузере.
  const сделатьУзел = документ.createElement;
  документ.createElement = function (тег) {
    const у = сделатьУзел(тег);
    у.showModal = function () {}; у.close = function () {}; у.animate = function () { return {}; };
    return у;
  };
  const исходник = [ПУТЬ_ДЕБЕРЦ, ПУТЬ_ЗАХВАТ, путьПанели].map(п => fs.readFileSync(п, 'utf8')).join('\n');
  const среда = поднять(исходник, { документ, имяФайла: 'панель-сказать' });
  const отправлено = [];
  среда.окно.Сеть = { послатьЭмоцию: async (номер, цель) => { отправлено.push({ номер, цель }); return { принято: true }; } };
  // Пока в каталоге «Захвата» нет нужнаЦель (Б3ф) — подкладываем свою: «Мир?» одному, «Бьём лидера!» всем.
  // Когда настоящая появится, подкладка её не трогает и проверка читает её.
  const зах = среда.окно.ЗахватЗнаки;
  if (зах && typeof зах.нужнаЦель !== 'function') зах.нужнаЦель = н => н === зах.ЭМОЦИИ.length + зах.ФРАЗЫ.indexOf('Мир?');
  const контекст = () => ({ поСети: true, я: 0, место: () => null, игроки: игроки || ОДИН_СОПЕРНИК });
  const панель = сДоводом ? среда.окно.ДеберцСказать(контекст, среда.окно.ЗахватЗнаки) : среда.окно.ДеберцСказать(контекст);
  панель.открыть();
  const вкладки = документ.querySelector('.панель-знаков__вкладки').children;
  function открытьВкладку(имя) {
    const в = вкладки.find(б => б.textContent === имя);
    if (!в) return null;
    в.onclick();
    return документ.querySelector('.ряд-знаков').children;
  }
  return { документ, панель, открытьВкладку, отправлено };
}

const подписи = кнопки => кнопки.map(б => б.getAttribute('aria-label'));
const ждать = () => new Promise(р => setImmediate(р));

async function прогнать(путьПанели) {
  // (1) без довода — каталог деберца
  {
    const с = собрать(путьПанели, false);
    const фразы = с.открытьВкладку('Фразы') || [];
    надо(фразы.length > 0, '(1) без довода: кнопки фраз найдены (ноль — провал)', 'найдено ' + фразы.length);
    надо(фразы.length === ДеберцЗнаки.ФРАЗЫ.length, '(1) без довода: число фраз как в js/деберц-знаки.js', фразы.length + ' из ' + ДеберцЗнаки.ФРАЗЫ.length);
    надо(JSON.stringify(подписи(фразы)) === JSON.stringify(ДеберцЗнаки.ФРАЗЫ), '(1) без довода: тексты фраз деберца');
  }
  // (2) с каталогом «Захвата»
  {
    const с = собрать(путьПанели, true);
    const фразы = с.открытьВкладку('Фразы') || [];
    надо(фразы.length > 0, '(2) с каталогом «Захвата»: кнопки фраз найдены (ноль — провал)', 'найдено ' + фразы.length);
    надо(фразы.length === ЗахватЗнаки.ФРАЗЫ.length, '(2) число фраз как в js/захват-знаки.js', фразы.length + ' из ' + ЗахватЗнаки.ФРАЗЫ.length);
    надо(JSON.stringify(подписи(фразы)) === JSON.stringify(ЗахватЗнаки.ФРАЗЫ), '(2) тексты фраз «Захвата»');
    const началоФраз = ЗахватЗнаки.ЭМОЦИИ.length, началоБросков = началоФраз + ЗахватЗнаки.ФРАЗЫ.length;
    фразы[0].onclick(); await ждать();
    надо(с.отправлено.length === 1 && с.отправлено[0].номер === началоФраз, '(2) первая фраза уходит под номером ' + началоФраз, JSON.stringify(с.отправлено));
    const сДругой = собрать(путьПанели, true);
    const броски = сДругой.открытьВкладку('Кинуть') || [];
    надо(броски.length > 0, '(2) вкладка «Кинуть»: кнопки найдены (ноль — провал)', 'найдено ' + броски.length);
    броски[0].onclick(); await ждать();
    надо(сДругой.отправлено.length === 1 && сДругой.отправлено[0].номер === началоБросков,
      '(2) «Кинуть» начинается с номера ' + началоБросков + ' (эмоции + фразы «Захвата»)', JSON.stringify(сДругой.отправлено));
  }
  // (3) принять(вид) с номером фразы «Захвата» показывает её текст
  {
    const с = собрать(путьПанели, true);
    const номер = ЗахватЗнаки.ЭМОЦИИ.length + 2;   // «Согласен» — не из каталога деберца под этим номером
    с.панель.принять({ код: 'К1', знакВнимания: { номер, порядковый: 1, этоЯ: false, имя: 'Соперник', от: 1 } });
    const что = с.документ.querySelector('#знаки-внимания .знак-внимания__что');
    надо(!!что, '(3) принять(вид): облако фразы появилось (ноль — провал)');
    надо(!!что && что.textContent === ЗахватЗнаки.текст(номер), '(3) принять(вид): показан текст фразы «Захвата»',
      что ? '«' + что.textContent + '» вместо «' + ЗахватЗнаки.текст(номер) + '»' : '');
  }
  const номерФразы = текст => ЗахватЗнаки.ЭМОЦИИ.length + ЗахватЗнаки.ФРАЗЫ.indexOf(текст);
  const нажатьФразу = (с, текст) => { const к = с.открытьВкладку('Фразы') || []; const б = к.find(x => x.getAttribute('aria-label') === текст); if (б) б.onclick(); return !!б; };
  // (4) «Мир?» одному игроку: ряд целей при двух соперниках, сразу — при одном
  {
    const с = собрать(путьПанели, true, ДВА_СОПЕРНИКА);
    надо(нажатьФразу(с, 'Мир?'), '(4) кнопка «Мир?» найдена (ноль — провал)');
    const ряд = с.документ.querySelector('#ряд-целей');
    const цели = ряд ? ряд.children.filter(б => (б.className || '').includes('кнопка--цель')) : [];
    надо(цели.length === 2, '(4) два соперника: ряд из 2 кнопок кнопка--цель (ноль — провал)', 'найдено ' + цели.length);
    const сообщение = с.документ.querySelector('.деберц-тихо');
    надо(!!сообщение && сообщение.textContent === 'Кому сказать «Мир?»?', '(4) текст «Кому сказать «Мир?»?»', сообщение ? '«' + сообщение.textContent + '»' : 'нет узла');
    надо(с.отправлено.length === 0, '(4) пока цель не выбрана — в сеть ничего не ушло', JSON.stringify(с.отправлено));
    if (цели.length === 2) {
      цели[1].onclick(); await ждать();
      надо(с.отправлено.length === 1 && с.отправлено[0].номер === номерФразы('Мир?') && с.отправлено[0].цель === ДВА_СОПЕРНИКА[1].id,
        '(4) нажатие на второго зовёт послатьЭмоцию(номер, id)', JSON.stringify(с.отправлено));
    }
    const один = собрать(путьПанели, true, ОДИН_СОПЕРНИК);
    нажатьФразу(один, 'Мир?'); await ждать();
    надо(один.отправлено.length === 1 && один.отправлено[0].цель === ОДИН_СОПЕРНИК[0].id && !один.документ.querySelector('#ряд-целей'),
      '(4) один соперник: уходит сразу с его id, ряда нет', JSON.stringify(один.отправлено));
  }
  // (5) «Бьём лидера!» — без ряда и без цели
  {
    const с = собрать(путьПанели, true, ДВА_СОПЕРНИКА);
    надо(нажатьФразу(с, 'Бьём лидера!'), '(5) кнопка «Бьём лидера!» найдена (ноль — провал)');
    await ждать();
    надо(!с.документ.querySelector('#ряд-целей'), '(5) ряда целей нет');
    надо(с.отправлено.length === 1 && с.отправлено[0].номер === номерФразы('Бьём лидера!') && с.отправлено[0].цель === undefined,
      '(5) уходит сразу, без цели', JSON.stringify(с.отправлено));
  }
  // (6) каталог деберца: ни у одной фразы ряда целей нет
  {
    надо(ДеберцЗнаки.ФРАЗЫ.length > 0, '(6) у деберца есть фразы (ноль — провал)');
    for (const текст of ДеберцЗнаки.ФРАЗЫ) {
      const с = собрать(путьПанели, false, ДВА_СОПЕРНИКА);
      const есть = нажатьФразу(с, текст); await ждать();
      надо(есть && !с.документ.querySelector('#ряд-целей') && с.отправлено.length === 1 && с.отправлено[0].цель === undefined,
        '(6) деберц, фраза «' + текст + '»: без ряда, уходит без цели', JSON.stringify(с.отправлено));
    }
  }
}

async function главная() {
  let путь = доводПути ? доводПути.slice('--панель='.length) : ПУТЬ_ПАНЕЛИ;
  if (сломать || сломатьЦель) {
    // Копия панели во временной папке: настоящий файл не трогаем. Режим --сломать — без второго довода,
    // --сломать-цель — где нужнаЦель не спрашивается (фраза уходит без выбора адресата).
    const исходник = fs.readFileSync(ПУТЬ_ПАНЕЛИ, 'utf8');
    const было = сломатьЦель ? '!З.нужнаЦель?.(номер)' : 'const З = каталог || window.ДеберцЗнаки;';
    const стало = сломатьЦель ? 'true' : 'const З = window.ДеберцЗнаки;';
    const испорчено = исходник.replace(было, стало);
    if (испорчено === исходник) { console.log('ПРОВАЛ: в панели нет портимой строки — портить нечего'); console.log('Итого проверок: 1, провалов: 1'); process.exit(1); }
    const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'сказать-каталог-'));
    путь = path.join(папка, 'деберц-сказать-сломанный.js');
    fs.writeFileSync(путь, испорчено);
    console.log('Ломающий запуск: копия панели без второго довода — ' + путь);
  }
  await прогнать(путь);
  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
}

главная().catch(е => { console.log('ПРОВАЛ: проверка упала: ' + (е && е.stack || е)); console.log('Итого проверок: ' + (проверок + 1) + ', провалов: ' + (провалов + 1)); process.exit(1); });
