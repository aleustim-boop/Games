'use strict';

/* =====================================================================
   Жалоба новичка: «выиграл две партии подряд — в таблице рекордов
   появились ДВЕ строки: „2 победы подряд“ и „1 победа подряд“».

   Что здесь выясняется. В js/telegram.js есть защита от таких ступенек:
   функция saveScore помнит последнюю записанную серию (переменная
   «последняяСерия») и, если пришёл результат ровно на одну победу больше
   и на том же уровне, не заводит новую строку, а растит старую. Пока игра
   открыта, это работает. Вопрос в другом: переменная живёт в памяти
   СТРАНИЦЫ, а длина серии — в памяти БРАУЗЕРА (js/game.js хранит её под
   ключом «подкидной-дурак:серия» и восстанавливает при запуске). Значит,
   после перезагрузки страницы игра помнит, что серия идёт, а хранилище
   рекордов — уже нет.

   Перезагрузка — это не редкость: Telegram Mini App запускается заново
   при каждом открытии из бота, а в браузере то же самое делает F5.

   Проверка играет обе истории — с перезагрузкой и без — и просто считает
   строки. Игру она не трогает: js/telegram.js запускается в поддельном
   браузере (пустое окно с поддельной памятью), как это уже сделано
   в tests/проверка-рекордов.js.

   Запуск: node tests/двойные-рекорды.js
   ===================================================================== */

const fs = require('fs');
const vm = require('vm');
const path = require('path');

const ИСХОДНИК = fs.readFileSync(path.join(__dirname, '..', 'js', 'telegram.js'), 'utf8');
const ИГРА = fs.readFileSync(path.join(__dirname, '..', 'js', 'game.js'), 'utf8');

/* ---------------------------------------------------------------------
   Поддельный браузер: память живёт отдельно от страницы, как в жизни
   --------------------------------------------------------------------- */

/** Память браузера понарошку. Переживает «перезагрузку страницы». */
function сделатьПамять() {
  const ящик = Object.create(null);
  return {
    ящик: ящик,
    getItem: function (ключ) {
      return Object.prototype.hasOwnProperty.call(ящик, ключ) ? ящик[ключ] : null;
    },
    setItem: function (ключ, значение) { ящик[ключ] = String(значение); },
    removeItem: function (ключ) { delete ящик[ключ]; }
  };
}

/**
 * «Открыть страницу»: запустить js/telegram.js заново поверх той же памяти
 * браузера. Это и есть перезагрузка — всё, что хранилось в переменных
 * страницы, забывается, а localStorage остаётся.
 */
function открытьСтраницу(память) {
  const окно = { localStorage: память, addEventListener: function () {} };
  const песочница = {
    window: окно,
    document: { documentElement: { style: { setProperty: function () {}, removeProperty: function () {} } } },
    Promise: Promise, setTimeout: setTimeout, clearTimeout: clearTimeout,
    JSON: JSON, Date: Date, Math: Math, Number: Number, String: String,
    Array: Array, Object: Object, Error: Error, isFinite: isFinite, console: console
  };
  песочница.globalThis = песочница;
  vm.createContext(песочница);
  vm.runInContext(ИСХОДНИК, песочница, { filename: 'js/telegram.js' });
  return { saveScore: окно.saveScore, loadScore: окно.loadScore };
}

/** Короткая запись таблицы: «3 обычный, 2 обычный». */
function словами(таблица) {
  return таблица.map((з) => з.очки + ' ' + з.сложность).join(' | ');
}

/* ---------------------------------------------------------------------
   Что игра помнит о серии между запусками
   --------------------------------------------------------------------- */

/**
 * Правда ли, что длина серии переживает перезагрузку страницы.
 * Спрашиваем не догадкой, а самим текстом js/game.js: там серия читается
 * из памяти браузера при запуске и записывается туда после каждой партии.
 */
function серияПереживаетПерезагрузку() {
  const ключ = /КЛЮЧ_СЕРИИ\s*=\s*'([^']+)'/.exec(ИГРА);
  const читаетПриЗапуске = /let\s+серияПобед\s*=\s*Math\.max\(0,\s*Number\(прочитатьНастройку\(КЛЮЧ_СЕРИИ\)\)/.test(ИГРА);
  const пишетПослеПартии = /записатьНастройку\(КЛЮЧ_СЕРИИ/.test(ИГРА);
  return { ключ: ключ ? ключ[1] : null, читаетПриЗапуске: читаетПриЗапуске, пишетПослеПартии: пишетПослеПартии };
}

/* ---------------------------------------------------------------------
   Истории
   --------------------------------------------------------------------- */

/** Две победы подряд, страницу не перезагружали. */
async function безПерезагрузки() {
  const память = сделатьПамять();
  const с = открытьСтраницу(память);
  await с.saveScore(1, 'обычный');
  await с.saveScore(2, 'обычный');
  const р = await с.loadScore();
  return р.таблица;
}

/** Две победы подряд, но между ними страницу открыли заново. */
async function сПерезагрузкой() {
  const память = сделатьПамять();
  const первая = открытьСтраницу(память);
  await первая.saveScore(1, 'обычный');
  const вторая = открытьСтраницу(память);       // ← перезагрузка
  await вторая.saveScore(2, 'обычный');
  const р = await вторая.loadScore();
  return р.таблица;
}

/** Пять побед подряд, и каждый раз игру открывали заново. */
async function пятьПобедСПерезагрузками() {
  const память = сделатьПамять();
  for (let победа = 1; победа <= 5; победа++) {
    const страница = открытьСтраницу(память);
    await страница.saveScore(победа, 'обычный');
  }
  const р = await открытьСтраницу(память).loadScore();
  return р.таблица;
}

/** То же, но у игрока уже были прошлые рекорды — что с ними станет. */
async function вытесняетЛиСтарое() {
  const память = сделатьПамять();
  const старые = [];
  // Восемь прошлых достижений: серии от 9 до 2 побед, добытые раньше.
  for (let очки = 9; очки >= 2; очки--) {
    старые.push({ очки: очки, дата: '01.01.2026', сложность: 'сложный' });
  }
  память.setItem('подкидной-дурак:рекорды', JSON.stringify({ лучший: 9, таблица: старые }));

  const былоСтрок = старые.length;
  for (let победа = 1; победа <= 5; победа++) {
    const страница = открытьСтраницу(память);   // каждый раз заново
    await страница.saveScore(победа, 'обычный');
  }
  const р = await открытьСтраницу(память).loadScore();
  const осталосьСтарых = р.таблица.filter((з) => з.дата === '01.01.2026').length;
  return { таблица: р.таблица, былоСтарых: былоСтрок, осталосьСтарых: осталосьСтарых };
}

/** Новая серия после проигрыша — так и должно быть отдельной строкой. */
async function новаяСерияПослеПроигрыша() {
  const память = сделатьПамять();
  const с = открытьСтраницу(память);
  await с.saveScore(1, 'обычный');
  await с.saveScore(2, 'обычный');
  // проиграл: серия обнулилась, игра начинает считать заново с единицы
  await с.saveScore(1, 'обычный');
  const р = await с.loadScore();
  return р.таблица;
}

/** Серия продолжается, но игрок поменял уровень соперника. */
async function сменаУровняВСередине() {
  const память = сделатьПамять();
  const с = открытьСтраницу(память);
  await с.saveScore(1, 'лёгкий');
  await с.saveScore(2, 'обычный');
  const р = await с.loadScore();
  return р.таблица;
}

/* ---------------------------------------------------------------------
   Прогон
   --------------------------------------------------------------------- */

async function главная() {
  console.log('Жалоба: «две победы подряд — две строки в рекордах». Проверяем счётом строк.');
  console.log('');

  const память = серияПереживаетПерезагрузку();
  console.log('Что игра помнит о серии между запусками (по тексту js/game.js):');
  console.log('   ключ в памяти браузера: ' + память.ключ);
  console.log('   длину серии читает при запуске: ' + (память.читаетПриЗапуске ? 'ДА' : 'нет'));
  console.log('   и записывает после партии: ' + (память.пишетПослеПартии ? 'ДА' : 'нет'));
  console.log('   → значит, после перезагрузки игра продолжает счёт серии,');
  console.log('     а хранилище рекордов о ней уже не помнит.');
  console.log('');

  const без = await безПерезагрузки();
  console.log('1. Две победы подряд, страницу не трогали:');
  console.log('   строк ' + без.length + ': ' + словами(без));

  const с = await сПерезагрузкой();
  console.log('2. Две победы подряд, между ними игру открыли заново:');
  console.log('   строк ' + с.length + ': ' + словами(с));

  const пять = await пятьПобедСПерезагрузками();
  console.log('3. Пять побед подряд, игру открывали заново перед каждой:');
  console.log('   строк ' + пять.length + ': ' + словами(пять));

  const вытеснение = await вытесняетЛиСтарое();
  console.log('4. У игрока было 8 прошлых рекордов (серии 9…2), потом пять побед с перезагрузками:');
  console.log('   в таблице ' + вытеснение.таблица.length + ' строк: ' + словами(вытеснение.таблица));
  console.log('   прошлых рекордов уцелело ' + вытеснение.осталосьСтарых + ' из ' + вытеснение.былоСтарых);

  const послеПроигрыша = await новаяСерияПослеПроигрыша();
  console.log('5. Две победы, проигрыш, снова победа (страницу не трогали):');
  console.log('   строк ' + послеПроигрыша.length + ': ' + словами(послеПроигрыша));

  const смена = await сменаУровняВСередине();
  console.log('6. Победа на лёгком, потом победа на обычном (серия та же):');
  console.log('   строк ' + смена.length + ': ' + словами(смена));

  console.log('');
  const ступенькиБезПерезагрузки = без.length > 1;
  const ступенькиСПерезагрузкой = с.length > 1;
  console.log('ИТОГ:');
  console.log('   без перезагрузки серия занимает ' + без.length +
    (ступенькиБезПерезагрузки ? ' строк — ступеньки есть' : ' строку — ступенек нет'));
  console.log('   с перезагрузкой серия занимает ' + с.length +
    (ступенькиСПерезагрузкой ? ' строк — СТУПЕНЬКИ ЕСТЬ' : ' строку — ступенек нет'));
  console.log('   пять побед с перезагрузками дают ' + пять.length +
    (пять.length === 1 ? ' строку — как и должно быть' : ' строк вместо одной'));
  console.log('   прошлых рекордов вытеснено: ' + (вытеснение.былоСтарых - вытеснение.осталосьСтарых));
  console.log('   смена уровня посреди серии: строк ' + смена.length +
    (смена.length === 1 ? ', подпись «' + смена[0].сложность + '»' : ' — серия разорвана на части'));
  process.exitCode = ступенькиСПерезагрузкой || пять.length > 1 ? 1 : 0;
}

главная().catch((сбой) => {
  console.error('Сорвалось: ' + сбой.message);
  process.exitCode = 1;
});
