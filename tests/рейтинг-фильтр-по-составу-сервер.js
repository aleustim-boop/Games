/* --------- Сама проверка --------- */

async function проверитьВсё() {
  console.log('1. Запрашиваем рейтинг через HTTP');
  const ответ = await спросить('/рейтинг', {
    initData: подписьИгрока(ИГРОК_1001, 'Игрок1001'),
    игра: 'дурак'
  });

  проверить(ответ.код === 200, 'статус код 200');
  проверить(ответ.тело.ок === true, 'ответ содержит ок: true');
  проверить(ответ.тело.узналиВас === true, 'ответ содержит узналиВас: true');

  console.log('2. Проверяем наличие поля поСоставу');
  проверить(typeof ответ.тело.поСоставу === 'object' && ответ.тело.поСоставу !== null,
    'поле поСоставу существует и это объект');

  if (typeof ответ.тело.поСоставу === 'object' && ответ.тело.поСоставу !== null) {
    console.log('3. Проверяем наличие личного и парами половин');
    проверить(typeof ответ.тело.поСоставу.личный === 'object' && ответ.тело.поСоставу.личный !== null,
      'поСоставу.личный существует и это объект');
    проверить(typeof ответ.тело.поСоставу.парами === 'object' && ответ.тело.поСоставу.парами !== null,
      'поСоставу.парами существует и это объект');

    const личный = ответ.тело.поСоставу.личный;
    const парами = ответ.тело.поСоставу.парами;

    console.log('4. Проверяем структуру каждой половины');
    if (личный) {
      проверить(typeof личный.всего === 'number', 'личный.всего — число');
      проверить(typeof личный.яВТаблице === 'boolean', 'личный.яВТаблице — булево');
      проверить(личный.верхушка && Array.isArray(личный.верхушка), 'личный.верхушка — массив');
      проверить(личный.вокругМеня && Array.isArray(личный.вокругМеня), 'личный.вокругМеня — массив');
      if (личный.яВТаблице) {
        проверить(typeof личный.я === 'object' && личный.я !== null, 'личный.я — объект, когда яВТаблице true');
      }
    }

    if (парами) {
      проверить(typeof парами.всего === 'number', 'парами.всего — число');
      проверить(typeof парами.яВТаблице === 'boolean', 'парами.яВТаблице — булево');
      проверить(парами.верхушка && Array.isArray(парами.верхушка), 'парами.верхушка — массив');
      проверить(парами.вокругМеня && Array.isArray(парами.вокругМеня), 'парами.вокругМеня — массив');
      if (парами.яВТаблице) {
        проверить(typeof парами.я === 'object' && парами.я !== null, 'парами.я — объект, когда яВТаблице true');
      }
    }

    console.log('5. Проверяем, что очки РАЗНЫЕ по составу');
    const личныйОчки = личный && личный.я ? личный.я.очки : null;
    const парамиОчки = парами && парами.я ? парами.я.очки : null;
    const общиеОчки = ответ.тело.я ? ответ.тело.я.очки : null;

    console.log('     Общие очки: ' + общиеОчки);
    console.log('     Личный: ' + личныйОчки);
    console.log('     Парами: ' + парамиОчки);

    проверить(typeof личныйОчки === 'number' && личныйОчки > 0,
      'личный.я.очки — положительное число (было: ' + личныйОчки + ')');
    проверить(typeof парамиОчки === 'number' && парамиОчки > 0,
      'парами.я.очки — положительное число (было: ' + парамиОчки + ')');
    проверить(личныйОчки !== парамиОчки,
      'личный и парами имеют РАЗНЫЕ очки (' + личныйОчки + ' vs ' + парамиОчки + ')');
    проверить(общиеОчки === личныйОчки + парамиОчки,
      'общие очки равны сумме личного и парами (' + общиеОчки + ' = ' + личныйОчки + ' + ' + парамиОчки + ')');
  }
}

/* --------- Запуск --------- */

(async function () {
  console.log('=== Рейтинг: фильтр по составу игроков (личный/парами) ===');
  console.log('Сервер на http://' + ХОЗЯИН + ':' + ПОРТ);
  console.log('Telegram поддельный, токен выдуманный, данные в ' + СВОЯ_ПАПКА);

  сервера.оснасткаДляПроверки(ТОКЕН_ДЛЯ_ПРОБЫ, function () { return { ok: true }; });
  const сервер = сервера.создатьСервер();

  await new Promise(function (готово, беда) {
    сервер.once('error', беда);
    сервер.listen(ПОРТ, ХОЗЯИН, готово);
  });

  let сбой = null;
  try {
    засеятьДанные();
    await проверитьВсё();
  } catch (беда) {
    сбой = беда;
  }

  /* Ждём, пока сервер полностью закроется, чтобы освободить порт. */
  await new Promise(function (готово) {
    сервер.close(готово);
  });
  сервера.оснасткаДляПроверки();

  console.log('\n----------------------------------------');
  if (сбой) {
    console.log('ПРОВЕРКА ОБОРВАЛАСЬ: ' + сбой.message);
    console.log(сбой.stack);
  }
  for (const беда of провалы) console.log('  - ' + беда);
  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалы.length);

  process.exit(сбой || провалы.length > 0 ? 1 : 0);
})();
