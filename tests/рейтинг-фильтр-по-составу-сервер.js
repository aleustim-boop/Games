/* =====================================================================
   РЕЙТИНГ: фильтр по составу игроков (личный / парами).

   Что проверяем. Маршрут /рейтинг сервера возвращает поле `поСоставу`
   с двумя половинами счёта — отдельно для личной игры (один на один) и
   игры парами (2 на 2). Каждая половина содержит те же структуры
   (верхушка, вокругМеня, я), но считанные по своей половине очков.
   Личные партии идут только в счёт «личный», парные партии (где игрок
   указан с напарником) — только в «парами».

   Что значит «ломающий запуск». Временно в коде подменяем вызов функции
   рейтинга.срезСоВсемиПравилами на рейтинг.срезДляИгрока. Это убирает оба
   поля (поПравилу и поСоставу) из ответа, и тесту нечего проверять —
   он краснеет на проверке наличия поСоставу.

   Запуск:
       node tests/рейтинг-фильтр-по-составу-сервер.js
       node tests/рейтинг-фильтр-по-составу-сервер.js 8797

   Ломающий запуск (обязан покраснеть):
       node tests/рейтинг-фильтр-по-составу-сервер.js --сломать

   Выход 0 — провалов нет, 1 — есть.
   ===================================================================== */

