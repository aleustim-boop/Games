let провалов = 0;
function проверить(условие, слова) {
  console.log((условие ? '  ок    — ' : '  ПЛОХО — ') + слова);
  if (!условие) провалов++;
}
const спать = (мс) => new Promise((ф) => setTimeout(ф, мс));

/** Нажать, если кнопка есть и видна. Нужно там, где путь стал короче:
    «Играть с ботом» теперь ведёт сразу за стол, и отдельной кнопки
    «Играть» на дороге может не быть вовсе. */
async function нажатьЕслиЕсть(страница, примета) {
  try {
    const видна = await страница.evaluate((п) => {
      const к = document.querySelector(п);
      return !!(к && к.offsetParent !== null);
    }, примета);
    if (!видна) return false;
    await страница.click(примета, { timeout: 4000 });
    return true;
  } catch (сбой) { return false; }
}

/** Что сейчас видно и что лежит под пальцем в точке кнопки. */
async function осмотретьКнопку(страница, примета) {
  return страница.evaluate((п) => {
    const к = document.querySelector(п);
    if (!к) return { есть: false };
    const место = к.getBoundingClientRect();
    const общее = {
      экраны: [...document.querySelectorAll('.экран.экран--виден')].map((э) => э.id),
      стрелкаТелеграма: !!(window.Telegram && window.Telegram.WebApp.BackButton && window.Telegram.WebApp.BackButton.isVisible),
      слушателейСтрелки: (window.__дневник && window.__дневник.события.backButtonClicked || []).length
    };
    /* Даже когда кнопки не видно, про стрелку Telegram сказать надо:
       иначе стенд объявит «уйти некуда», хотя системная стрелка есть.
       На этом он уже соврал один раз. */
    if (место.width < 1 || место.height < 1) return Object.assign({ есть: true, видна: false }, общее);
    const x = место.left + место.width / 2;
    const y = место.top + место.height / 2;
    const подПальцем = document.elementFromPoint(x, y);
    const свой = подПальцем === к || к.contains(подПальцем);
    const экраны = [...document.querySelectorAll('.экран.экран--виден')].map((э) => э.id);
    return {
      есть: true, видна: true,
      подПальцем: подПальцем ? (подПальцем.id || подПальцем.className || подПальцем.tagName) : '(пусто)',
      перекрыта: !свой,
      где: Math.round(место.top) + '…' + Math.round(место.bottom),
      экраны: экраны,
      стрелкаТелеграма: !!(window.Telegram && window.Telegram.WebApp.BackButton && window.Telegram.WebApp.BackButton.isVisible),
      слушателейСтрелки: (window.__дневник && window.__дневник.события.backButtonClicked || []).length
    };
  }, примета);
}

/** Нажать и посмотреть, изменилось ли хоть что-нибудь. */
async function нажатьИПосмотреть(страница, примета, ждатьМс) {
  const до = await страница.evaluate(() => ({
    экраны: [...document.querySelectorAll('.экран.экран--виден')].map((э) => э.id).join(','),
    адрес: location.pathname
  }));
  try {
    await страница.click(примета, { timeout: 3000 });
  } catch (сбой) {
    return { нажалось: false, до: до, после: до, причина: 'нажать не вышло: ' + String(сбой).slice(0, 60) };
  }
  await спать(ждатьМс || 700);
  const после = await страница.evaluate(() => ({
    экраны: [...document.querySelectorAll('.экран.экран--виден')].map((э) => э.id).join(','),
    адрес: location.pathname
  }));
  return { нажалось: true, до: до, после: после, изменилось: до.экраны !== после.экраны || до.адрес !== после.адрес };
}

/**
 * «Назад», как его делает человек в Telegram: с 11 сентября оформление
 * прячет «‹» на рекордах, правилах, оформлении и рейтинге — там уходят
 * стрелкой самого Telegram. Видна кнопка — жмём её, нет — стрелку.
 */
async function назадИПосмотреть(страница, примета, ждатьМс) {
  const видна = await страница.locator(примета).isVisible().catch(() => false);
  if (видна) {
    const ответ = await нажатьИПосмотреть(страница, примета, ждатьМс);
    ответ.чем = 'кнопкой';
    return ответ;
  }
  const до = await страница.evaluate(() => ({
    экраны: [...document.querySelectorAll('.экран.экран--виден')].map((э) => э.id).join(','),
    адрес: location.pathname
  }));
  const нажали = await страница.evaluate(() => {
    if (!window.ПоддельныйТелеграм) return false;
    window.ПоддельныйТелеграм.нажатьНазад();
    return true;
  });
  await спать(ждатьМс || 700);
  const после = await страница.evaluate(() => ({
    экраны: [...document.querySelectorAll('.экран.экран--виден')].map((э) => э.id).join(','),
    адрес: location.pathname
  }));
  return { нажалось: нажали, до: до, после: после, чем: 'стрелкой Telegram',
    изменилось: до.экраны !== после.экраны || до.адрес !== после.адрес,
    причина: нажали ? '' : 'ни кнопки, ни стрелки Telegram' };
}

async function новаяСтраница(браузер, размер) {
  const окно = await браузер.newContext({ viewport: { width: размер.ш, height: размер.в }, hasTouch: true });
  const страница = await окно.newPage();
  const красные = [];
  страница.on('pageerror', (о) => красные.push('падение: ' + о.message));
  страница.on('console', (м) => {
    if (м.type() !== 'error') return;
    const откуда = (м.location && м.location() && м.location().url) || '';
    if (/telegram-web-app\.js/.test(м.text() + ' ' + откуда)) return;
    красные.push('консоль: ' + м.text());
  });
  await подготовитьПодделку(страница, { версия: '8.0', полныйЭкран: 'дают' });
  return { окно, страница, красные };
}

