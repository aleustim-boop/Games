/* =====================================================================
   ВСЕ КНОПКИ «НАЗАД» — ГДЕ ОНА НЕ СРАБАТЫВАЕТ.

   Владелец: «кнопка назад не всегда работает». «Не всегда» — значит
   искать надо СЛУЧАЙ, а не кнопку. Поэтому здесь каждая «Назад»
   проверяется не одним нажатием, а четырьмя вопросами:

     1. КУДА ВЕДЁТ — помнит ли, откуда пришли, или всегда в одно место;
     2. РАБОТАЕТ ЛИ ПОСЛЕ ДЕЙСТВИЯ — после партии, после плашки итога,
        после открытой панели знаков;
     3. НЕ ПЕРЕКРЫТА ЛИ — проверяем не глазом, а пальцем: что лежит
        в той точке, куда попадёт палец (document.elementFromPoint);
     4. НЕ СЪЕДАЕТСЯ ЛИ НАЖАТИЕ — у нас есть защита от двойного касания;
        жмём «Назад» сразу после другой кнопки.

   Проверяются три игры: дурак (index.html), шашки, шахматы.

   Запуск (страничный сервер уже поднят):
       node tests/кнопки-назад-везде.js 8080
   ===================================================================== */

