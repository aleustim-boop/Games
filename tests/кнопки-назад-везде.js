    await спать(500);

    const до = await осмотретьКнопку(страница, '#кнопка-назад');
    console.log('  «Назад» на доске: ' + JSON.stringify(до));
    const телеграмнаяЕсть = до.стрелкаТелеграма && до.слушателейСтрелки > 0;
    console.log('  своя стрелка видна: ' + до.видна + ', телеграмная слушается: ' + телеграмнаяЕсть);
