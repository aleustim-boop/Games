'use strict';

/* =====================================================================
   ПЕРЕИСПОЛЬЗОВАНИЕ КОДА КОМНАТЫ: старый игрок не падает в новую комнату.

   Что проверяем. Коды комнат конечны и переиспользуются; когда старая
   комната с кодом X умирает и код X достаётся совсем новой комнате,
   игрок, запомнивший X по старому списку столов (вместе с родиласьТогда),
   не должен молча попасть в чужую новую комнату.

   Механизм: столОткрытДляПосадки обязан отказать словами
   «Этот стол уже закрылся — выберите другой из списка»,
   если родиласьТогда не совпадает с комната.создана.

   Проверяем:
     — старый игрок с устаревшим родиласьТогда не может сесть (можно: false);
     — новый игрок с правильным родиласьТогда может сесть (можно: true);
     — флаг одноразовый: третья комната НЕ получает переданный код без
       нового вызова задатьКодСледующейКомнатыДляПроверки.

   Выход 0 — провалов нет, 1 — есть.
   ===================================================================== */

const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const комнаты = require(path.join(КОРЕНЬ, 'server', 'комнаты.js'));

const ЛОМАТЬ = process.argv.indexOf('--сломать') !== -1;
if (ЛОМАТЬ) {
  console.log('*** ЛОМАЮЩИЙ ЗАПУСК: передаём undefined вместо родиласьТогда — ' +
              'сверка пропускается, старый игрок попадёт в новую комнату — проверка обязана покраснеть ***');
}

let проверок = 0;
const провалы = [];

function проверить(условие, что) {
  проверок++;
  if (!условие) {
    провалы.push(что);
    console.log('  ПРОВАЛ ' + проверок + ': ' + что);
  } else {
    console.log('  ок ' + проверок + ': ' + что);
  }
}

/* Локальная обёртка для проверки защиты родиласьТогда.
   В режиме --сломать передаём undefined вместо родиласьТогда,
   чтобы функция пропустила сверку (см. комментарий в server/комнаты.js:
   «Не передали время (старый вызов) — сверку пропускаем, как раньше»).
   Это настоящий путь в коде, не подделка. */
function сесть(код, родиласьТогда) {
  return комнаты.столОткрытДляПосадки(код, ЛОМАТЬ ? undefined : родиласьТогда);
}

function проверитьВсё() {
  const адрес = '127.0.0.1:9999';

  console.log('1. Создание и настройка комнаты А');
  // Создаём открытую комнату А для шашек
  const результатА = комнаты.создатьКомнату(адрес, {
    игра: 'шашки',
    открытый: true,
    имя: 'Игрок А'
  });

  проверить(результатА.ок === true, 'Комната А создана успешно (ок: true)');
  проверить(typeof результатА.код === 'string' && результатА.код.length > 0,
    'Комната А получила код');

  const кодА = результатА.код;
  console.log('  Код комнаты А: ' + кодА);

  // Находим стол А в списке открытых столов
  console.log('2. Поиск комнаты А в списке открытых столов');
  const открытыеШашки = комнаты.открытыеСтолы('шашки');
  проверить(Array.isArray(открытыеШашки), 'открытыеСтолы возвращает массив');

  let столА = null;
  for (const стол of открытыеШашки) {
    if (стол.код === кодА) {
      столА = стол;
      break;
    }
  }

  проверить(столА !== null, 'Комната А видна в списке открытых столов');
  проверить(typeof столА.родиласьТогда === 'number' && столА.родиласьТогда > 0,
    'У комнаты А есть родиласьТогда (временная метка)');

  const родиласьТогдаА = столА.родиласьТогда;
  console.log('  родиласьТогда комнаты А: ' + родиласьТогдаА);

  // Удаляем комнату А
  console.log('3. Удаление комнаты А');
  комнаты.удалитьКомнату(кодА);
  const открытыеПосле = комнаты.открытыеСтолы('шашки');
  let нашлиА = false;
  for (const стол of открытыеПосле) {
    if (стол.код === кодА) {
      нашлиА = true;
      break;
    }
  }
  проверить(нашлиА === false, 'Комната А удалена и больше не видна в списке');

  // Задаём код для следующей комнаты
  console.log('4. Подготовка кода для комнаты Б');
  комнаты.задатьКодСледующейКомнатыДляПроверки(кодА);
  console.log('  Задали код: ' + кодА + ' для следующей комнаты');

  // Создаём комнату Б с тем же кодом
  console.log('5. Создание комнаты Б (должна получить код комнаты А)');
  const результатБ = комнаты.создатьКомнату(адрес, {
    игра: 'шашки',
    открытый: true,
    имя: 'Игрок Б'
  });

  проверить(результатБ.ок === true, 'Комната Б создана успешно (ок: true)');
  проверить(результатБ.код === кодА,
    'Комната Б получила ровно тот же код, что был у комнаты А');

  // Находим стол Б в списке открытых столов
  console.log('6. Поиск комнаты Б в списке открытых столов');
  const открытыеШашкиБ = комнаты.открытыеСтолы('шашки');
  let столБ = null;
  for (const стол of открытыеШашкиБ) {
    if (стол.код === кодА) {
      столБ = стол;
      break;
    }
  }

  проверить(столБ !== null, 'Комната Б видна в списке открытых столов');
  проверить(typeof столБ.родиласьТогда === 'number' && столБ.родиласьТогда > 0,
    'У комнаты Б есть родиласьТогда');

  const родиласьТогдаБ = столБ.родиласьТогда;
  console.log('  родиласьТогда комнаты Б: ' + родиласьТогдаБ);
  проверить(родиласьТогдаБ !== родиласьТогдаА,
    'родиласьТогда у Б отличается от родиласьТогда у А (разные комнаты)');

  // ГЛАВНАЯ ПРОВЕРКА: старый игрок с кодом А и старым родиласьТогда не может сесть
  console.log('7. Главная проверка: старый игрок (старое время) не может сесть');
  const попыткаСеста = сесть(кодА, родиласьТогдаА);
  проверить(попыткаСеста.можно === false,
    'столОткрытДляПосадки(кодА, старое родиласьТогда) вернул можно: false');
  проверить(typeof попыткаСеста.причина === 'string' && попыткаСеста.причина.length > 0,
    'Причина отказа заполнена: ' + попыткаСеста.причина);

  // ПОЗИТИВНЫЙ КОНТРОЛЬ: новый игрок с правильным родиласьТогда может сесть
  console.log('8. Позитивный контроль: новый игрок (правильное время) может сесть');
  const попыткаСестаПравильно = комнаты.столОткрытДляПосадки(кодА, родиласьТогдаБ);
  проверить(попыткаСестаПравильно.можно === true,
    'столОткрытДляПосадки(кодА, правильное родиласьТогда) вернул можно: true');

  // Проверка одноразовости флага
  console.log('9. Проверка одноразовости флага');
  const результатВ = комнаты.создатьКомнату(адрес, {
    игра: 'шашки',
    открытый: true,
    имя: 'Игрок В'
  });

  проверить(результатВ.ок === true, 'Комната В создана успешно');
  проверить(результатВ.код !== кодА,
    'Комната В получила ДРУГОЙ код (флаг был одноразовый)');
  console.log('  Код комнаты В: ' + результатВ.код);

  // Опция: проверяем, что флаг действительно сброшен
  // Сначала удаляем комнату Б (она ещё существует с кодом кодА)
  комнаты.удалитьКомнату(кодА);

  комнаты.задатьКодСледующейКомнатыДляПроверки(кодА);
  const результатГ = комнаты.создатьКомнату(адрес, {
    игра: 'шашки',
    открытый: true,
    имя: 'Игрок Г'
  });
  проверить(результатГ.код === кодА,
    'Новый вызов задатьКодСледующейКомнатыДляПроверки(кодА) работает: комната Г получила кодА');

  // Чистота: удаляем все созданные комнаты
  комнаты.удалитьКомнату(результатГ.код);
  комнаты.удалитьКомнату(результатВ.код);
}

/* =====================================================================
   Запуск
   ===================================================================== */

(function () {
  console.log('=== Переиспользование кода комнаты ===\n');


  let сбой = null;
  try {
    проверитьВсё();
  } catch (беда) {
    сбой = беда;
  }

  console.log('\n----------------------------------------');
  if (сбой) {
    console.log('ПРОВЕРКА ОБОРВАЛАСЬ: ' + сбой.message);
    console.log(сбой.stack);
  }
  for (const беда of провалы) console.log('  - ' + беда);
  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалы.length);

  process.exit(сбой || провалы.length > 0 ? 1 : 0);
})();
