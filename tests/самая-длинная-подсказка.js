/**
 * Ход человека: играем просто и законно, лишь бы партия шла. Зовём ровно
 * те же функции, что и кнопки на экране, — тогда и сообщения получаются
 * настоящие, а не собранные нами вручную.
 */
function сходитьЗаЧеловека(игра) {
  return игра.спросить(
    '(function () {' +
    '  if (!партия || партия.завершена) return "партии нет";' +
    '  if (ктоХодит(партия) !== "человек") return "не наш ход";' +
    '  var рука = партия.руки.человек;' +
    '  if (фаза(партия) === "защита") {' +
    '    var пара = -1;' +
    '    for (var п = 0; п < партия.стол.length; п++) { if (!партия.стол[п].защита) { пара = п; break; } }' +
    '    if (пара >= 0) {' +
    '      for (var i = 0; i < рука.length; i++) {' +
    '        if (бьёт(рука[i], партия.стол[пара].атака, партия.козырь)) { отбитьсяКартой(пара, i); return "отбился"; }' +
    '      }' +
    '    }' +
    '    нажатьБеру(); return "беру";' +
    '  }' +
    '  for (var к = 0; к < рука.length; к++) {' +
    '    if (можноПоложить(партия, рука[к])) { сходитьКартой(к); return "положил"; }' +
    '  }' +
    '  нажатьБито(); return "бито";' +
    '})()');
}

/* ---------------------------------------------------------------------
   ОТКАЗЫ — вторая половина того, что вообще бывает в строке подсказки.

   ЗАЧЕМ ЭТО ДОБАВИЛИ. Раньше замер видел только рассказы о ходах («Соперник
   подкинул Д♦») и напоминания о действии («Отбивайтесь — выберите карту»).
   А в ту же самую строку — в её левую половину, вместо рассказа — ложатся
   слова отказа: то, что игра отвечает на нажатие по карте, которой сейчас
   нельзя. Пока отказы были короткими («Этой картой не отбиться» — 24 знака),
   их отсутствие в замере ничего не портило. Теперь отказ называет причину
   целой фразой («6♦ не побьёт К♠ — нужна ♠ старше или козырь»), и не считать
   его больше нельзя: рекорд может стоять именно на нём.

   КАК СОБИРАЕМ. Ни одна строка отказа сюда не переписана. Мы просто ТЫКАЕМ
   пальцем во всё, во что может ткнуть живой человек, зовя ровно те же
   обработчики, что висят на элементах страницы:

     • по каждой карте своей руки — и обязательно ДВАЖДЫ подряд: на повтор
       игра отвечает другими словами («Зелёная черта…»), и эта вторая строка
       тоже должна попасть в замер;
     • по каждой карте на столе;
     • по стопке колоды и по подписи козыря;
     • мимо карт — в просвет полосы руки.

   Что при этом получится — отказ или законный ход, — решает сама игра.
   В части 2 (стол компанией) законный ход уходит на сервер, а сервера
   в замере нет, и игра отвечает своим же отказом «Связи с игрой нет» —
   стол от этого не меняется, положение остаётся тем же.

   ОТЧЕГО ЧИСЛО ОТКАЗОВ РАНЬШЕ ВРАЛО — и как это вылечено. Замер считал
   отказом ЛЮБУЮ строку, прочитанную после тычка. А тычок отказом
   кончается не всегда:

     • тычок мог оказаться законным ходом или просто поднять карту —
       тогда в строке стоит обычный рассказ о ходе, отказа не было вовсе;
     • строку в этот миг могла занимать пара «событие · напоминание»,
       и левую половину этой пары подаёт сам замер, а не игра.

   Отсюда в выводе и мелькало «самый длинный отказ 88 знаков»
   («Сейчас ходит Александра-Мария · Этой картой можно только перевести»),
   какого игра не рисует: настоящий отказ, пока он свежий, занимает
   строку ОДИН, без напоминания справа.

   Теперь после каждого тычка спрашиваем саму игру, отказ ли это:
   у неё для этого есть собственная пометка «событиеЭтоОтказ» — та самая,
   по которой она и решает отдать строку отказу целиком. Своей мерки
   не выдумываем: выдумай мы её здесь — она разошлась бы с игрой молча.
   --------------------------------------------------------------------- */

function потыкатьВоВсё(игра) {
  return игра.спросить(
    '(function () {' +
    '  var строки = [];' +
    '  if (!партия || партия.завершена) return строки;' +
    /* Глухоту руки после кнопки снимаем: она бережёт живой палец от «хвоста»
       касания, а нам мешает — тычки просто пропадали бы молча, и часть
       отказов не попала бы в замер ни разу. Мы меряем длину слов, а не её. */
    '  рукаГлухаДо = 0;' +
    /* Читаем строку И пометку игры разом: отказ ли это. «событиеЭтоОтказ»
       живёт в самой игре и появилась там не для нас — по ней игра решает,
       отдать ли строку отказу целиком. */
    '  var читать = function () {' +
    '    return { текст: document.getElementById("подсказка-текст").textContent || "",' +
    '             отказ: (typeof событиеЭтоОтказ !== "undefined") && событиеЭтоОтказ === true };' +
    '  };' +
    '  var рука = (партия.руки && партия.руки.человек) ? партия.руки.человек.length : 0;' +
    '  for (var i = рука - 1; i >= 0; i--) {' +
    '    тапПоКартеЧеловека(i); строки.push(читать());' +
    '    тапПоКартеЧеловека(i); строки.push(читать());' +   // повтор: другие слова
    '  }' +
    '  for (var п = 0; п < партия.стол.length; п++) {' +
    '    тапПоПаре(п); строки.push(читать());' +
    '    тапПоПаре(п); строки.push(читать());' +
    '  }' +
    '  тапПоКолоде(); строки.push(читать());' +
    '  тапПоКозырю(); строки.push(читать());' +
    '  тапМимоКарты({ target: { id: "карты-человека" } }); строки.push(читать());' +
    '  return строки;' +
    '})()') || [];
}

async function замерВдвоём() {
  const игра = поднятьИгру();
  const собранные = копилка();
  const отказы = копилка();      // строки, полученные тычками, — считаем и отдельно
  let ходов = 0;
  let тычков = 0;

  for (let номерПартии = 1; номерПартии <= ПАРТИЙ; номерПартии++) {
    игра.спросить('начатьПартию()');
    собранные.положить(игра.подсказка());

    /* Ход бота игра назначает таймером, поэтому просто ждём: таймеры
       в песочнице настоящие. Партия против бота идёт около полуминуты
       машинного времени, поэтому срок берём с запасом. */
    const крайний = Date.now() + 90000;
    while (игра.спросить('!!партия && !партия.завершена') && Date.now() < крайний) {
      /* Сначала тычем во всё подряд — как нетерпеливый человек, который
         ждёт хода соперника и трогает свои карты, — и только потом ходим
         законно. Тычем и в свой ход, и в чужой: отказы у них разные. */
      for (const ответ of потыкатьВоВсё(игра)) {
        собранные.положить(ответ.текст);          // строка была на экране — она в счёт
        if (ответ.отказ) отказы.положить(ответ.текст);   // а отказом её зовёт сама игра
        тычков++;
      }
      if (игра.спросить('!!партия && !партия.завершена && ктоХодит(партия) === "человек"')) {
        сходитьЗаЧеловека(игра);
        ходов++;
        собранные.положить(игра.подсказка());
      }
      await пауза(20);
      собранные.положить(игра.подсказка());
    }
    собранные.положить(игра.подсказка());
    // не даём накопиться отложенным делам между партиями
    await пауза(30);
  }

  return { строки: собранные.все(), отказы: отказы.все(), ходов: ходов, тычков: тычков };
}

/* =====================================================================
   ЧАСТЬ 2. СТОЛ КОМПАНИЕЙ

   Тут игра устроена иначе, и мерить приходится иначе тоже. Вдвоём игра
   всё придумывает сама, а компанией она только показывает то, что прислал
   сервер: и рассказ о событии, и «чей сейчас ход», и «можно ли подкинуть».
   Поэтому собираем строку так же, как она собирается у живого игрока:

       настоящая партия  →  настоящий видДляИгрока (сервер)
                         →  настоящий показатьВид (страница)
                         →  читаем строку с экрана

   ЗАЧЕМ ТРИ ДЛИНЫ ИМЕНИ. Имя подставляется сразу в обе половинки строки,
   поэтому от его длины рекорд едет вдвое быстрее, чем кажется. И это три
   разных ответа на три разных вопроса: короткое имя показывает, сколько
   места занимают сами слова игры; обычное — что видит обычный игрок;
   предельное — с чем вёрстка обязана справиться при самом длинном имени,
   какое сервер вообще пропускает.
   ===================================================================== */

/**
 * Виды событий — все, какие знает сервер. Берём не список, переписанный
 * сюда, а собственные списки сервера: поднимаем его исходник отдельно
 * и спрашиваем имена ключей. Так новая фраза попадает в замер сама,
 * а мы не рискуем измерять вчерашний набор.
 */
function видыСобытийСервера() {
  const песочница = {
    require: function (куда) {
      return require(path.resolve(path.dirname(ПУТЬ_К_СЕРВЕРУ), куда));
    },
    module: { exports: {} },
    console: console, Math: Math, Date: Date, JSON: JSON,
    Number: Number, String: String, Array: Array, Object: Object,
    Error: Error, isFinite: isFinite, setTimeout: setTimeout, clearTimeout: clearTimeout
  };
  песочница.exports = песочница.module.exports;
  песочница.globalThis = песочница;
  vm.createContext(песочница);
  vm.runInContext(fs.readFileSync(ПУТЬ_К_СЕРВЕРУ, 'utf8'), песочница,
                  { filename: 'server/партия-по-сети.js' });
  return {
    сИсполнителем: vm.runInContext('Object.keys(РАССКАЗ_О_СОБЫТИИ)', песочница),
    общие: vm.runInContext('Object.keys(ОБЩИЕ_СОБЫТИЯ)', песочница)
  };
}

/**
 * Три имени для замера. Предельное не выписано числом, а обрезано по мерке
 * самого сервера: поменяют там потолок — замер поедет за ним следом.
 */
function именаДляЗамера() {
  const предельное = 'Александра-Мариянна'.slice(0, сеть.ДЛИНА_ИМЕНИ);
  return [
    { какое: 'короткое', имя: 'Ян' },
    { какое: 'обычное', имя: 'Бот 3' },        // так звали соседа в жалобе живого игрока
    { какое: 'предельное', имя: предельное }
  ];
}

/**
 * Места за столом: имя у всех одно и то же — то, которое меряем.
 *
 * Почему у всех, а не только у соседей. Строка называет по имени двоих
 * сразу: слева того, кто что-то сделал, справа того, кого ждут. Это разные
 * люди, и в самом тесном случае оба носят длинное имя. Дать длинное имя
 * только одному значило бы померить случай полегче настоящего.
 *
 * Своё имя тоже настоящее, а не слово «Вы»: первый замер назвал моё место
 * «Вы», и на экране соседа выходило «Вы берёт — подкинуть нечем» — беда
 * не игры, а замера. Игра сама зовёт себя «Вы» там, где надо (см. «своё»
 * в рассказах сервера), и подсказывать ей это именем не нужно.
 */
function местаСИменем(партия, имя) {
  return партия.игроки.map(function (ключ, номер) {
    return {
      ключ: ключ,
      имя: имя,
      этоБот: номер !== 0,
      хозяин: номер === 0,
      наСвязи: true
    };
  });
}

/**
 * Все рассказы о событии, какие сервер может прислать этому игроку.
 * Текст собирает сам сервер своей же функцией — ни одна строка сюда
 * не переписана.
 */
function рассказыСервера(имя, места) {
  const виды = видыСобытийСервера();
  const выход = [];
  const добавить = function (что, чей, текст) {
    if (текст) выход.push({ что: что, чей: чей, текст: текст });
  };
  for (const что of виды.сИсполнителем) {
    // «своё» — это сделал я сам; «чужое» — это сделал сосед, и его назовут по имени.
    добавить(что, 'своё', сеть.текстСобытия({ что: что, кто: 'человек' }, 'человек', места, true));
    добавить(что, 'чужое', сеть.текстСобытия({ что: что, кто: 'бот-3', имя: имя }, 'человек', места, true));
  }
  for (const что of виды.общие) {
    добавить(что, 'общее', сеть.текстСобытия({ что: что }, 'человек', места, true));
  }
  return выход;
}

/* ---------------------------------------------------------------------
   Настоящие положения стола

   Играем обычные партии компанией правилами игры и её же ботом, а один
   игрок ходит «пугливо»: пасует, имея карты, и берёт, хотя мог бы
   отбиться. Так делает живой человек — и только так стол попадает
   в положения, где слово идёт по кругу и фразы становятся длиннее.
   --------------------------------------------------------------------- */

/** Слепок положения, чтобы вернуться к нему потом. Карты — простые записи. */
function слепокПартии(партия) {
  return JSON.parse(JSON.stringify({
    игроки: партия.игроки, руки: партия.руки, стол: партия.стол,
    колода: партия.колода, отбой: партия.отбой, козырь: партия.козырь,
    козырнаяКарта: партия.козырнаяКарта, атакует: партия.атакует,
    берёт: партия.берёт, пасы: партия.пасы || [], выбывшие: партия.выбывшие || [],
    завершена: партия.завершена, результат: партия.результат || '',
    проигравшие: партия.проигравшие || [], размерКолоды: партия.размерКолоды,
    парами: партия.парами === true, переводной: партия.переводной === true,
    сложность: партия.сложность
  }));
}

/** Один ход за того, чьё слово: обычно ботом игры, иногда — пугливо. */
function сходитьЗаСтолом(партия, пугливый) {
  const кто = правила.ктоХодит(партия);
  if (!кто) return false;
  const фаза = правила.фаза(партия);

  if (кто === пугливый) {
    if (фаза === 'защита') {
      if (правила.объявитьБеру(партия)) return true;
    } else if (фаза === 'подкидывание' || фаза === 'докидывание') {
      if (правила.пас(партия, кто)) return true;
    }
  }
  правила.ходБота(партия, кто);
  return true;
}

/**
 * Слова отказа, какие это положение вообще может породить, — спрашиваем
 * у самой игры её же двумя объяснялками. Ничего при этом не двигается:
 * обе только составляют фразу и в стол не лезут.
 *
 * Нужно это вот зачем. Образцы положений раньше отбирались по НЕПОХОЖЕЙ
 * ФРАЗЕ ДЕЙСТВИЯ, и таких фраз всего семнадцать — значит, и столов для
 * замера оставалось семнадцать. Для рассказов сервера этого хватало
 * (они от стола не зависят), а вот отказ зависит от стола целиком:
 * «Подкидывают только то, что уже на столе: 6, 7, 8, 9, 10, В или Д» —
 * это ровно про то, какие карты сейчас лежат. Отбирая по фразе действия,
 * мы такие столы почти все и выбрасывали, а рекорд стоит как раз на них.
 */
function отказыПоложения(игра) {
  return игра.спросить(
    '(function () {' +
    '  var из = [];' +
    '  if (!партия || !партия.руки || !партия.руки.человек) return из;' +
    '  var р = партия.руки.человек;' +
    '  for (var i = 0; i < р.length; i++) {' +
    '    из.push(почемуНельзяПоложить(р[i]));' +
    '    из.push(почемуНельзяОтбиться(р[i]));' +
    '  }' +
    '  return из;' +
    '})()') || [];
}

/**
 * Сыграть партии компанией и запомнить по одному образцу на каждую
 * непохожую фразу действия — и на каждые непохожие слова отказа тоже.
 * Имя здесь нарочно нейтральное: важна не сама фраза, а положение стола,
 * которое её порождает, — имена подставим потом.
 */
/**
 * «Вид» отказа: те же слова, но без самих карт. «6♦ не побьёт К♠» и
 * «10♣ не побьёт Т♥» — один вид, и хранить оба положения незачем.
 */
function видОтказа(текст) {
  return String(текст).replace(/[0-9ВДКТ♠♥♦♣]/g, '#').replace(/#[#,\s]*/g, '# ');
}

function собратьПоложения(игра) {
  const образцы = new Map();     // фраза при нейтральном имени → слепок положения
  const виделиОтказ = new Set(); // какие виды отказа уже встречались
  let самыйДлинныйОтказ = 0;     // рекорд длины отказа: за ним и гонимся
  const раскладки = [
    { игроков: 3 }, { игроков: 4 }, { игроков: 6 },
    { игроков: 3, переводной: true }, { игроков: 4, парами: true }
  ];
  let номерСобытия = 0;
  let положений = 0;

  const показать = function (партия, места, кто) {
    const вид = сеть.видДляИгрока(партия, кто, { места: места, номерСобытия: ++номерСобытия });
    игра.песочница.__вид = вид;
    игра.спросить('window.ИграПоСети.показатьВид(__вид)');
  };

  for (const настройки of раскладки) {
    for (let н = 1; н <= ПАРТИЙ_КОМПАНИЕЙ; н++) {
      const партия = правила.создатьПартию(настройки);
      const места = местаСИменем(партия, 'Игрок');
      // Пугливым делаем то одного, то другого — иначе половина стола
      // ведёт себя одинаково и часть положений не встречается вовсе.
      const пугливый = партия.игроки[н % партия.игроки.length];

      for (let шаг = 0; шаг < 400 && !партия.завершена; шаг++) {
        for (const кто of партия.игроки) {
          if (!правила.вИгре(партия, кто)) continue;
          показать(партия, места, кто);
          положений++;
          const фраза = игра.спросить('текстДействия()');
          if (фраза && !образцы.has(фраза)) {
            образцы.set(фраза, { слепок: слепокПартии(партия), кто: кто, выбранная: null });
          }
          /* Стол, который умеет отказать по-новому, тоже берём в образцы:
             отказ пишет в строку то, что лежит на этом самом столе.

             Брать подряд каждый непохожий отказ нельзя — их тысячи (у каждой
             пары карт свои слова), и замер стал бы вечным. Берём только два
             случая: невиданный ВИД отказа (слова те же, карты другие — вид
             один) и отказ ДЛИННЕЕ всех прежних. Второе и есть погоня
             за рекордом, ради которого всё считается. */
          for (const слова of отказыПоложения(игра)) {
            if (!слова) continue;
            const вид = видОтказа(слова);
            const новыйВид = !виделиОтказ.has(вид);
            const длиннее = слова.length > самыйДлинныйОтказ;
            if (!новыйВид && !длиннее) continue;
            виделиОтказ.add(вид);
            if (длиннее) самыйДлинныйОтказ = слова.length;
            образцы.set('отказ: ' + слова, { слепок: слепокПартии(партия), кто: кто, выбранная: null });
          }
          /* Отдельно — с поднятой картой: человек берёт карту в руку,
             и подсказка меняется. Поднимаем по очереди каждую. */
          const вРуке = партия.руки[кто].length;
          for (let i = 0; i < вРуке; i++) {
            const сКартой = игра.спросить('выбраннаяКарта = ' + i + '; текстДействия()');
            if (сКартой && !образцы.has(сКартой)) {
              образцы.set(сКартой, { слепок: слепокПартии(партия), кто: кто, выбранная: i });
            }
          }
          игра.спросить('выбраннаяКарта = null;');
        }
        if (!сходитьЗаСтолом(партия, пугливый)) break;
      }

      /* Доигранная партия — тоже положение: строка не пустует между
         последним ходом и экраном итога, там стоит «Партия окончена». */
      if (партия.завершена) {
        for (const кто of партия.игроки) {
          показать(партия, места, кто);
          положений++;
          const фраза = игра.спросить('текстДействия()');
          if (фраза && !образцы.has(фраза)) {
            образцы.set(фраза, { слепок: слепокПартии(партия), кто: кто, выбранная: null });
          }
        }
      }
    }
  }
  return { образцы: образцы, положений: положений };
}

/**
 * Померить одно имя: расставить его за столом, показать каждое положение
 * и в каждом перебрать все рассказы сервера. Строку читаем с экрана —
 * склеивает её сама игра, мы только смотрим.
 *
 * Каждая строка помечается видом события («забрал», «вернулся»). Пометка
 * нужна дальше, чтобы отделить пары, которые бывают у живого игрока,
 * от пар, которые можно только составить на бумаге.
 */
function померитьИмя(игра, образцы, имя) {
  const строки = [];
  const половинки = { рассказы: new Map(), фразы: копилка() };
  const отказыОтдельно = копилка();   // те же строки, но только полученные тычком
  let номерСобытия = 1000;

  const показать = function (образец, рассказ) {
    const партия = образец.слепок;
    const добавка = { места: местаСИменем(партия, имя), номерСобытия: ++номерСобытия };
    if (рассказ) добавка.событие = рассказ;
    const вид = сеть.видДляИгрока(партия, образец.кто, добавка);
    игра.песочница.__вид = вид;
    игра.спросить('window.ИграПоСети.показатьВид(__вид)');
    // Поднятую карту игра опускает сама, когда рука меняется, — возвращаем
    // её так же, как это делает тап по карте, и просим перерисовать строку.
    if (образец.выбранная !== null) {
      игра.спросить('выбраннаяКарта = ' + образец.выбранная + '; рисоватьПодсказкуИКнопки();');
    }
    return игра.подсказка();
  };

  // Рассказы сервера считаем один раз: от положения стола они не зависят.
  const первый = образцы.values().next().value;
  const рассказы = рассказыСервера(имя, местаСИменем({ игроки: первый.слепок.игроки }, имя));

  /* Две подписи игра сочиняет сама, и попадают они в ту же строку:
     «Первым ходит такой-то» в начале партии и «Сейчас ходит такой-то» —
     в ответ на тап не в свою очередь. Спрашиваем их у самой игры,
     показав ей сперва любое положение. */
  показать(первый, null);
  рассказы.push({ что: 'первый-ход', чей: 'игра', текст: игра.спросить('текстПервогоХода()') });
  рассказы.push({ что: 'не-ваш-ход', чей: 'игра', текст: игра.спросить('текстНеВашХод()') });
  for (const рассказ of рассказы) {
    if (рассказ.текст) половинки.рассказы.set(рассказ.текст, рассказ.что);
  }

  for (const образец of образцы.values()) {
    // Сперва без нового события — так видна чистая фраза действия.
    строки.push({ текст: показать(образец, null), что: 'без события' });
    половинки.фразы.положить(игра.спросить('текстДействия()'));
    /* Тычки. Делаем их сразу после чистого показа, пока на столе то самое
       положение: отказ ложится в ту же строку вместо рассказа о ходе.
       Отказом зовём не всякую прочитанную строку, а ту, которую сама игра
       пометила отказом (см. пояснение у «потыкатьВоВсё»): тычок мог
       оказаться и законным ходом, и тогда в строке стоит рассказ о нём. */
    for (const ответ of потыкатьВоВсё(игра)) {
      строки.push({ текст: ответ.текст, что: ответ.отказ ? 'отказ' : 'после тычка' });
      if (ответ.отказ) отказыОтдельно.положить(ответ.текст);
    }
    for (const рассказ of рассказы) {
      if (!рассказ.текст) continue;
      строки.push({ текст: показать(образец, рассказ.текст), что: рассказ.что });
    }
  }

  return {
    строки: строки,
    рассказы: Array.from(половинки.рассказы.keys()).sort(function (а, б) { return б.length - а.length; }),
    чтоЗаРассказ: половинки.рассказы,
    фразы: половинки.фразы.все(),
    отказы: отказыОтдельно.все()
  };
}

/**
 * Самые длинные строки из измеренных. Можно попросить только те, чьё
 * событие вправду застаёт партию за игрой, — список таких событий
 * приносит живая комната.
 *
 * Отказы этот отбор не касается вовсе, и вот почему. Отбор нужен, чтобы
 * не сложить рассказ о событии с положением стола, при котором такого
 * события не бывает. У отказа складывать нечего: он не приходит со стороны,
 * а рождается прямо здесь — от нажатия человека по этому самому столу.
 * Ткнуть в свои карты можно в любом положении, значит и пара законна всегда.
 */
function самыеДлинные(строки, толькоЭти) {
  const видел = new Set();
  const выход = [];
  for (const строка of строки) {
    /* «После тычка» пропускаем наравне с отказом: это тоже ответ самой игры
       на нажатие по этому самому столу, а не пара, склеенная замером. */
    if (толькоЭти && строка.что !== 'без события' && строка.что !== 'отказ' &&
        строка.что !== 'после тычка' && !толькоЭти.has(строка.что)) continue;
    if (!строка.текст || видел.has(строка.текст)) continue;
    видел.add(строка.текст);
    выход.push(строка.текст);
  }
  выход.sort(function (а, б) { return б.length - а.length; });
  return выход;
}

/* =====================================================================
   ЖИВАЯ КОМНАТА: какие события вообще застают партию за игрой

   Зачем это нужно, хотя рекорд считается и без этого. Если сложить все
   рассказы со всеми фразами подряд, получатся пары, которых у живого
   игрока не бывает никогда: «Ян возвращает всех в прихожую — стол
   собирают заново» рядом с «Укажите карту на столе» — это стол, который
   уже разобрали, и карт на нём нет. Пойди штаб укорачивать по такой
   паре — он резал бы текст, который никому не мешает, и не тронул бы тот,
   который мешает всем.

   Поэтому спрашиваем не себя, а сам сервер комнат: поднимаем настоящую
   комнату на троих, играем в ней настоящую партию его же дверями
   и смотрим, при каком событии партия ещё идёт, а при каком её уже нет.
   Список «эти события бывают во время партии» получается у сервера,
   а не переписан сюда руками.

   Отдельно проверяем случай, из-за которого этот файл сегодня и правили:
   у одного игрока «уснул телефон» (сервер вывел его за молчание), а потом
   он вернулся. Тогда остальные читают самую длинную фразу в игре —
   «возвращается за стол — дальше играет вместо бота», — и читают её
   ПОСРЕДИ ПАРТИИ, рядом с обычной подсказкой про ход.
   ===================================================================== */

/** Простой игрок для живой комнаты: ходит по тем же полям, что видит человек. */
function решитьЗаИгрока(вид, пасоватьРано, переводить) {
  const стол = вид.стол || [];
  const рука = вид.мояРука || [];
  if (вид.фаза === 'защита') {
    if (!вид.яОтбиваюсь) return null;
    // Иногда переводим: без этого событие «переводит ход» не встретится вовсе.
    if (переводить && вид.могуПеревести) {
      const достоинства = new Set();
      for (const пара of стол) if (пара.атака) достоинства.add(пара.атака.имя);
      for (let i = 0; i < рука.length; i++) {
        if (достоинства.has(рука[i].имя)) return { действие: 'перевести', карта: i };
      }
    }
    for (let п = 0; п < стол.length; п++) {
      if (стол[п].защита) continue;
      for (let i = 0; i < рука.length; i++) {
        const своя = рука[i];
        const чужая = стол[п].атака;
        const бьёт = своя.масть === чужая.масть
          ? своя.вес > чужая.вес
          : своя.масть === вид.козырь && чужая.масть !== вид.козырь;
        if (бьёт) return { действие: 'отбить', пара: п, карта: i };
      }
    }
    return { действие: 'беру' };
  }
  if (!вид.яХожу) return null;
  if (вид.фаза === 'атака') return { действие: 'ходить', карта: 0 };
  if (вид.фаза === 'подкидывание' || вид.фаза === 'докидывание') {
    if (пасоватьРано || !вид.могуПодкинуть) return { действие: 'бито' };
    const достоинства = new Set();
    for (const пара of стол) {
      if (пара.атака) достоинства.add(пара.атака.имя);
      if (пара.защита) достоинства.add(пара.защита.имя);
    }
    for (let i = 0; i < рука.length; i++) {
      if (достоинства.has(рука[i].имя)) return { действие: 'ходить', карта: i };
    }
    return { действие: 'бито' };
  }
  return null;
}

function сыгратьВЖивойКомнате(игра, имя) {
  const комнаты = require(path.join(КОРЕНЬ, 'server', 'комнаты.js'));
  const собранные = копилка();
  const приЖивойПартии = new Set();
  const всеВстреченные = new Set();
  const коды = [];

  /* Собрать комнату-компанию на троих: хозяин и два гостя, у всех одно
     и то же имя (см. местаСИменем — там сказано, почему у всех). */
  const собратьКомнату = function (мест, гостей) {
    const создано = комнаты.создатьКомнату('127.0.0.1', { мест: мест || 3, имя: имя });
    if (!создано.ок) return null;
    коды.push(создано.код);
    const найден = комнаты.найтиИгрока(создано.код, создано.пропуск);
    const стол = {
      код: создано.код,
      комната: найден.комната,
      хозяин: найден.ктоЯ,
      гости: [],
      пропуска: {}
    };
    стол.пропуска[стол.хозяин] = создано.пропуск;
    const сколькоГостей = гостей === undefined ? (мест || 3) - 1 : гостей;
    for (let i = 0; i < сколькоГостей; i++) {
      const вошёл = комнаты.войтиВКомнату(создано.код, { имя: имя, метка: 'страница-' + коды.length + '-' + i });
      if (!вошёл.ок) break;
      const кто = комнаты.найтиИгрока(создано.код, вошёл.пропуск).ктоЯ;
      стол.пропуска[кто] = вошёл.пропуск;
      стол.гости.push(кто);
    }
    стол.заСтолом = [стол.хозяин].concat(стол.гости);
    return стол;
  };

  /* Посмотреть комнату глазами каждого и прочитать строку с экрана.
     Заодно записываем, при каком событии партия ещё идёт: только это
     и отличает пару, которую человек увидит, от пары «на бумаге».

     Страницу дёргаем ровно тогда, когда её дёргает js/сеть.js, — то есть
     когда комната уже не в прихожей. В прихожей строки подсказки нет
     вовсе, и показывать ей стол значит выдумывать положение, которого
     у живого игрока не бывает. */
  const оглядеться = function (стол) {
    for (const кто of стол.заСтолом) {
      const вид = комнаты.показатьИгроку(стол.комната, кто);
      if (вид.видСобытия) {
        всеВстреченные.add(вид.видСобытия);
        if (вид.фаза && вид.фаза !== 'конец' && !вид.завершена) приЖивойПартии.add(вид.видСобытия);
      }
      if (вид.этап === 'ожидание') continue;
      игра.песочница.__вид = вид;
      игра.спросить('window.ИграПоСети.показатьВид(__вид)');
      собранные.положить(игра.подсказка());
    }
  };

  const начатьПартию = function (стол, переводной) {
    комнаты.сделатьХод(стол.комната, стол.хозяин, { действие: 'настройки', переводной: переводной === true });
    оглядеться(стол);
    комнаты.сделатьХод(стол.комната, стол.хозяин, { действие: 'начать' });
    оглядеться(стол);
  };

  /* --- Комната первая: полная партия со всеми ходами --- */
  const первый = собратьКомнату();
  if (!первый) {
    return { строки: [], приЖивойПартии: приЖивойПартии, всеВстреченные: всеВстреченные,
             беда: 'сервер не дал создать комнату' };
  }
  оглядеться(первый);                                   // прихожая: «входит в комнату»
  начатьПартию(первый, true);

  /* По дороге один гость «засыпает» (сервер выводит его за молчание)
     и возвращается — ровно то, из-за чего в игре появилась самая
     длинная фраза: «возвращается за стол — дальше играет вместо бота». */
  let уснулИВернулся = false;
  for (let шаг = 0; шаг < 400; шаг++) {
    const чей = сеть.чейХод(первый.комната.партия);
    if (!чей || первый.комната.этап !== 'игра') break;

    if (!уснулИВернулся && шаг === 6 && первый.гости.length > 0) {
      const соня = первый.гости.find(function (г) { return г !== чей; });
      if (соня) {
        комнаты.выйти(первый.комната, соня, true);        // телефон уснул
        оглядеться(первый);
        комнаты.найтиИгрока(первый.код, первый.пропуска[соня]);   // и человек вернулся
        оглядеться(первый);
        уснулИВернулся = true;
        continue;
      }
    }

    const вид = комнаты.показатьИгроку(первый.комната, чей);
    /* Каждый третий отказывается подкидывать рано, каждый второй переводит:
       иначе половина событий за партию не встречается вовсе. */
    const решение = решитьЗаИгрока(вид, шаг % 3 === 0, шаг % 2 === 0);
    if (!решение) break;
    const ответ = комнаты.сделатьХод(первый.комната, чей, решение);
    if (ответ && ответ.принято === false && решение.действие !== 'бито') {
      комнаты.сделатьХод(первый.комната, чей, { действие: 'бито' });
    }
    оглядеться(первый);
  }

  // Конец партии: «предлагает сыграть ещё» и новая раздача.
  комнаты.сделатьХод(первый.комната, первый.хозяин, { действие: 'ещё' });
  оглядеться(первый);
  for (const гость of первый.гости) {
    комнаты.сделатьХод(первый.комната, гость, { действие: 'ещё' });
    оглядеться(первый);
  }

  /* --- Пробные комнаты: остальные события, каждое в свежей комнате ---

     Эти действия партию рушат или заканчивают, поэтому каждое пробуем
     отдельно и на новом столе. Спрашиваем ровно одно: жива ли партия
     в тот миг, когда игрок читает про это событие. Ответ решает, войдёт
     ли фраза в рекорд, — и добывать его надо у сервера, а не из головы. */
  const пробы = [
    /* «Возвращает всех в прихожую». Посреди партии сервер этого не даёт
       («Партия ещё идёт»), поэтому пробуем дважды: сперва во время партии —
       чтобы своими глазами убедиться в отказе, — потом после её конца. */
    { мест: 3, партия: true, сделать: function (с) {
      комнаты.сделатьХод(с.комната, с.хозяин, { действие: 'пересобрать' }); } },
    { мест: 4, гостей: 2, партия: false, сделать: function (с) {   // «сажает бота» и «убирает бота»
      комнаты.сделатьХод(с.комната, с.хозяин, { действие: 'бот', место: 4 });
      оглядеться(с);
      комнаты.сделатьХод(с.комната, с.хозяин, { действие: 'убрать-бота' }); } },
    { мест: 3, партия: true, сделать: function (с) {          // «выходит из игры — доигрывает бот»
      if (с.гости.length) комнаты.выйти(с.комната, с.гости[0], false); } },
    { мест: 2, партия: true, сделать: function (с) {          // «выходит из игры — партия закончена»
      if (с.гости.length) комнаты.выйти(с.комната, с.гости[0], false);
      оглядеться(с);
      // Партии больше нет — вот теперь стол пересобирается, и событие приходит.
      комнаты.сделатьХод(с.комната, с.хозяин, { действие: 'пересобрать' }); } },
    { мест: 3, партия: false, сделать: function (с) {         // «выходит из комнаты» (прихожая)
      if (с.гости.length) комнаты.выйти(с.комната, с.гости[0], false); } }
  ];
  for (const проба of пробы) {
    const стол = собратьКомнату(проба.мест, проба.гостей);
    if (!стол) continue;
    if (проба.партия) начатьПартию(стол, false);
    проба.сделать(стол);
    оглядеться(стол);
  }

  for (const код of коды) комнаты.удалитьКомнату(код);
  комнаты.остановитьУборку();
  return {
    строки: собранные.все(),
    приЖивойПартии: приЖивойПартии,
    всеВстреченные: всеВстреченные,
    беда: ''
  };
}

