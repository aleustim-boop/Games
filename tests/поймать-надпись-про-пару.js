/* =====================================================================
   ПОЙМАТЬ НАДПИСЬ «Подход мимо вас — играет напарник» (и её вторую половину
   «Подход мимо вас — напарник берёт карты»).

   ЭТО НЕ АВТОПРОГОН ДЛЯ NODE. Файл вставляется в консоль браузера, когда
   игра уже открыта (http://127.0.0.1:8123/index.html) и стоит в меню.

   ЗАЧЕМ. Надпись показывается сама, в середине партии парами, и поймать
   её руками трудно: за один вечер можно не встретить ни разу, а можно
   встретить трижды за партию. Эта ловушка играет партии сама (тем же
   «пальцем», что и tests/автоигрок-в-браузере.js) и записывает КАЖДЫЙ
   миг, когда надпись висит на экране, вместе с тем, что в этот миг
   нарисовано на плашках соперников.

   ПОЧЕМУ СВЕРЯЕМ ИМЕННО С ПЛАШКАМИ. Надпись называет напарника прямо,
   а на плашке напарник помечен рамкой и подписью «отбивается». Если
   надпись и плашки говорят разное — человек видит противоречие глазами,
   и неважно, кто из них прав. Поэтому ловушка не спрашивает правила,
   а смотрит на экран: у той плашки, где стоит метка «отбивается»,
   обязана стоять и метка «напарник».

   ЧТО ОНА СЧИТАЕТ:
     - «под своим же ходом» — человек в этот миг сам нападает или
       отбивается (его карта на столе, кнопки его). Тогда надпись врёт
       в лицо: подход не мимо него;
     - «отбивается не напарник» — метки на плашках не сошлись;
     - «напарник назван дважды» — правило трёх надписей: напарник назван
       И в пилюле «Вы» (#статус-хода), И в подсказке одновременно. Это
       повтор, который человек видит глазами;
     - «напарник берёт карты» — он сказал «Беру». С 11 сентября это только
       справка, не беда: подсказка стала «Подход мимо вас — ждите» и про
       напарника ничего не утверждает, так что врать ей тут не о чем;
     - «мигание» — сколько раз за партию надпись зажигалась заново.

   КАК ПОЛЬЗОВАТЬСЯ (игра открыта, вы в меню):
       await Ловушка.начать();   // играет партии парами, пока не наберёт показы
       Ловушка.отчёт();          // что поймала
       Ловушка.стоп();

   Ничего в игре ловушка не меняет: только нажимает кнопки и читает экран.
   ===================================================================== */

(function () {
  'use strict';

  /* Слова в игре с тех пор переписывали дважды. Сперва строка стала короче
     и честнее («Подход мимо вас — играет напарник» / «…— напарник берёт
     карты»), 11 сентября — ещё короче: «Подход мимо вас — ждите», без
     напарника вовсе (правило трёх надписей: кто отбивается, видно на его
     месте). Начало у всех вариантов одно, ловушка ловит именно его.
     Со старой фразой ловушка молча набирала ноль показов за дюжину партий
     и выглядела так, будто всё в порядке. */
  const ФРАЗА = 'Подход мимо вас';

  /** Имя напарника — как оно написано на его месте за столом. */
  function имяНапарника() {
    const узел = document.querySelector('.соперник.соперник--напарник .соперник__имя');
    return узел ? (узел.textContent || '').trim() : '';
  }

  /** Называет ли текст напарника: словом «напарник» или его именем. */
  function называетНапарника(текст, имя) {
    const т = String(текст || '').toLowerCase();
    if (т.indexOf('напарник') !== -1) return true;
    return Boolean(имя) && т.indexOf(имя.toLowerCase()) !== -1;
  }
  const ПОКАЗОВ_ХВАТИТ = 8;
  const ПАРТИЙ_ПОТОЛОК = 40;

  const с = {
    работает: false, партий: 0, показов: 0, шаговСНадписью: 0,
    подСвоимХодом: 0, отбиваетсяНеНапарник: 0, напарникБерёт: 0, напарникДважды: 0,
    миганийВПартии: 0, максМиганий: 0, партийСМиганием: 0,
    записи: [], лента: [], горит: false, ждёмИтога: false,
    текстыПодписи: {}
  };

  function эл(id) { return document.getElementById(id); }
  function узелПодсказки() { return эл('подсказка-текст') || эл('подсказка'); }
  function видЭкрана(id) { const у = эл(id); return у && у.classList.contains('экран--виден'); }
  /** Заглянуть внутрь игры — только чтение, ничего не меняем. */
  function внутри(что) { try { return (0, eval)(что); } catch (e) { return null; } }

  /** Что нарисовано на плашках соперников прямо сейчас. */
  function чтоНаПлашках() {
    const плашки = [].slice.call(document.querySelectorAll('.соперник'));
    const отбивается = плашки.filter(function (п) {
      return п.classList.contains('соперник--отбивается');
    });
    return {
      всего: плашки.length,
      ктоОтбивается: отбивается.map(function (п) {
        const имя = п.querySelector('.соперник__имя');
        return (имя ? имя.textContent : '?').trim();
      }),
      отбивающийсяЭтоНапарник: отбивается.length === 1 &&
        отбивается[0].classList.contains('соперник--напарник'),
      подписиОтбивающегося: отбивается.map(function (п) {
        const роль = п.querySelector('.соперник__роль');
        const метка = п.querySelector('.соперник__метка');
        return [(роль ? роль.textContent : ''), (метка ? метка.textContent : '')]
          .filter(Boolean).join(' / ').trim();
      })
    };
  }

  /** Играет ли человек прямо сейчас сам: его карта на столе или его слово. */
  function яВЭтомПодходе() {
    const п = внутри('партия');
    if (!п) return false;
    const яОтбиваюсь = внутри('этоЯОтбиваюсь') ? внутри('этоЯОтбиваюсь()') : false;
    const мойХод = внутри('сейчасМойХод') ? внутри('сейчасМойХод()') : false;
    return Boolean(мойХод || яОтбиваюсь || (п.атакует === 'человек' && п.стол.length > 0));
  }

  function записатьМиг(текст, зажглась) {
    const п = внутри('партия');
    const плашки = чтоНаПлашках();
    const фаза = внутри('фаза') ? внутри('фаза(партия)') : '';
    const своё = яВЭтомПодходе();
    const берёт = Boolean(п && п.берёт);
    /* Правило трёх надписей: напарник назван и в пилюле «Вы», и в подсказке
       разом — это повтор. Одна подсказка без напарника повтором не бывает. */
    const пилюля = ((эл('статус-хода') || {}).textContent || '').trim();
    const имя = имяНапарника();
    const дважды = называетНапарника(текст, имя) && называетНапарника(пилюля, имя);

    с.шаговСНадписью++;
    if (зажглась) с.показов++;
    if (своё) с.подСвоимХодом++;
    if (!плашки.отбивающийсяЭтоНапарник) с.отбиваетсяНеНапарник++;
    // Справка, не беда: подсказка про напарника ничего не утверждает.
    if (берёт || фаза === 'докидывание') с.напарникБерёт++;
    if (дважды) с.напарникДважды++;
    с.текстыПодписи[текст] = (с.текстыПодписи[текст] || 0) + 1;

    const плохо = своё || !плашки.отбивающийсяЭтоНапарник || дважды;
    if (плохо && с.записи.length < 30) {
      с.записи.push({
        беда: [своё ? 'человек играет сам' : '',
               !плашки.отбивающийсяЭтоНапарник ? 'на плашке отбивается НЕ напарник' : '',
               дважды ? 'напарник назван дважды: в пилюле «' + пилюля + '» и в подсказке' : ''].filter(Boolean).join('; '),
        строкаНаЭкране: текст,
        пилюля: пилюля,
        фаза: фаза,
        наПлашкеОтбивается: плашки.ктоОтбивается.join(','),
        подписьПлашки: плашки.подписиОтбивающегося.join(','),
        картНаСтоле: п ? п.стол.length : null,
        пропущеноПодходов: внутри('подходовМимоМеня'),
        былЯвЭтомПодходе: внутри('былЯвЭтомПодходе')
      });
    }
  }

  function следить() {
    const узел = узелПодсказки();
    if (!узел) return;
    const т = (узел.textContent || '').trim();
    if (т !== с.лента[с.лента.length - 1]) {
      с.лента.push(т);
      if (с.лента.length > 30) с.лента.shift();
    }
    const горит = т.indexOf(ФРАЗА) !== -1;
    if (горит) {
      if (!с.горит) с.миганийВПартии++;
      записатьМиг(т, !с.горит);
    }
    с.горит = горит;
  }

  function подвести() {
    с.партий++;
    if (с.миганийВПартии > с.максМиганий) с.максМиганий = с.миганийВПартии;
    if (с.миганийВПартии > 2) с.партийСМиганием++;
    с.миганийВПартии = 0;
    с.лента = [];
  }

  /* Поставить стол «вчетвером, парами» и начать партию.

     Настройки стола и кнопка «Играть» переехали с первого экрана на новый
     экран «Игра с ботом»: в начале теперь спрашивают, с кем играть. Поэтому
     сперва заходим туда, а уж потом жмём кнопки стола. */
  function начатьПартиюПарами() {
    const режимБот = эл('кнопка-режим-бот');
    if (режимБот) режимБот.click();
    const кнопки = [].slice.call(document.querySelectorAll('#меню-выбор-мест .кнопка'));
    const четыре = кнопки.filter(function (к) { return (к.textContent || '').trim() === '4'; })[0];
    if (четыре) четыре.click();
    const парами = [].slice.call(document.querySelectorAll('#меню-выбор-пар button'))
      .filter(function (к) { return (к.textContent || '').indexOf('Парами') !== -1; })[0];
    if (парами) парами.click();
    const играть = эл('кнопка-играть');
    if (играть) играть.click();
  }

  function шаг() {
    if (!с.работает) return;
    следить();
    if (видЭкрана('экран-результата')) {
      if (!с.ждёмИтога) { с.ждёмИтога = true; подвести(); }
      if (с.показов >= ПОКАЗОВ_ХВАТИТ || с.партий >= ПАРТИЙ_ПОТОЛОК) {
        с.работает = false; window.Автоигрок.стоп(); return;
      }
      const ещё = эл('кнопка-ещё');
      if (ещё) { ещё.click(); setTimeout(function () { window.Автоигрок.начать(0.5, false); }, 300); }
    } else {
      с.ждёмИтога = false;
      if (видЭкрана('экран-меню') || видЭкрана('экран-бота')) начатьПартиюПарами();
      else if (видЭкрана('экран-игры') && !window.Автоигрок.работает()) window.Автоигрок.начать(0.5, false);
    }
    setTimeout(шаг, 120);
  }

  window.Ловушка = {
    начать: async function () {
      if (!window.Автоигрок) {
        const о = await fetch('tests/автоигрок-в-браузере.js'); (0, eval)(await о.text());
      }
      if (!window.УскорительПауз) {
        const о = await fetch('tests/ускоритель-пауз-в-браузере.js'); (0, eval)(await о.text());
      }
      window.УскорительПауз.включить();
      с.работает = true;
      шаг();
      return 'играю парами и жду надпись; спрашивайте Ловушка.отчёт()';
    },
    стоп: function () { с.работает = false; if (window.Автоигрок) window.Автоигрок.стоп(); return 'стоп'; },
    идёт: function () { return с.работает; },
    отчёт: function () {
      return {
        партийСыграно: с.партий,
        зажиганийНадписи: с.показов,
        шаговСНадписьюНаЭкране: с.шаговСНадписью,
        подСвоимЖеХодом: с.подСвоимХодом,
        отбиваетсяНеНапарник: с.отбиваетсяНеНапарник,
        напарникНазванДважды: с.напарникДважды,
        // Справка: с 11 сентября это не беда (подсказка про напарника молчит).
        напарникНеОтбивалсяАБрал: с.напарникБерёт,
        партийСМиганием: с.партийСМиганием,
        рекордЗажиганийЗаПартию: с.максМиганий,
        какиеСтрокиВидели: с.текстыПодписи,
        плохиеМиги: с.записи
      };
    }
  };
  console.log('Ловушка готова: await Ловушка.начать()');
})();
