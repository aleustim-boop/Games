/* Проверка: дашборд штаба прогревает данные «Онлайн» при старте.
   Без сети и без настоящей боевой машины: хаб (штаб/вм.js) подменён
   заглушкой, запрос к местному серверу комнат (http.get) — тоже, сервер
   дашборда встаёт на свободный порт (0), а не на 8791.

   Требует:
     (а) при старте запрос «Онлайн» (вызов хаба) сделан ровно один раз
         до любого захода на страницу;
     (б) сбой запроса при старте не роняет дашборд (и хаб отказал, и сама
         страница «Онлайн» бросила ошибку);
     (в) первый заход после прогрева получает данные, а не «спрашиваю…».

   Запуск:            node tests/дашборд-онлайн-прогрев.js
   Ломающий запуск:   node tests/дашборд-онлайн-прогрев.js --сломать <папка вне проекта>
     Делает в этой папке КОПИЮ штаб/дашборд.js, убирает в копии вызов прогрева
     и прогоняет те же проверки на копии — обязан дать провал (код 1).
     Настоящий файл проекта не трогается. Замена, не нашедшая строку, — тоже
     провал (сообщение «ЗАМЕНА НЕ НАШЛА»). */

'use strict';

const fs = require('fs');
const http = require('http');
const path = require('path');

const КОРЕНЬ = path.resolve(__dirname, '..');
const НАСТОЯЩИЙ_ДАШБОРД = path.join(КОРЕНЬ, 'штаб', 'дашборд.js');
const ХАБ_ЗАДЕРЖКА_МС = 2500;  // дольше, чем страница ждёт хаб (2 с): без прогрева заход «спрашивает»

let провалов = 0;
let всего = 0;

function проверить(имя, условие, подробность) {
  всего++;
  if (условие) {
    console.log('  ок      ' + имя);
  } else {
    провалов++;
    console.log('  ПРОВАЛ  ' + имя + (подробность ? ' — ' + подробность : ''));
  }
}

function пауза(мс) {
  return new Promise(function (готово) { setTimeout(готово, мс); });
}

/** В режиме --сломать готовит копию дашборда во временной папке и отдаёт путь к ней. */
function путьКДашборду() {
  const место = process.argv.indexOf('--сломать');
  if (место === -1) return НАСТОЯЩИЙ_ДАШБОРД;

  const папка = process.argv[место + 1];
  if (!папка) {
    console.log('ПРОВАЛ: после --сломать нужна папка вне проекта');
    process.exit(1);
  }
  const полная = path.resolve(папка);
  const отКорня = path.relative(КОРЕНЬ, полная);
  if (!отКорня.startsWith('..') || path.isAbsolute(отКорня)) {
    // Внутри проекта копий не делаем; на другом диске relative даёт абсолютный путь — это «вне».
    if (!path.isAbsolute(отКорня)) {
      console.log('ПРОВАЛ: папка для копии должна быть вне проекта: ' + полная);
      process.exit(1);
    }
  }
  fs.mkdirSync(полная, { recursive: true });

  let текст = fs.readFileSync(НАСТОЯЩИЙ_ДАШБОРД, 'utf8');
  // Копия лежит в другой папке — её «./сбор.js» и прочие подключения ведём на настоящие модули.
  const штабПрямо = path.join(КОРЕНЬ, 'штаб').replace(/\\/g, '/');
  текст = текст.split("require('./").join("require('" + штабПрямо + '/');

  const строкаПрогрева = '    прогретьОнлайн();\n';
  if (текст.split(строкаПрогрева).length !== 2) {
    console.log('ПРОВАЛ: ЗАМЕНА НЕ НАШЛА вызов прогрева в дашборд.js (или их не один) — проверка не может краснеть');
    process.exit(1);
  }
  текст = текст.replace(строкаПрогрева, '');

  const копия = path.join(полная, 'дашборд-без-прогрева.js');
  fs.writeFileSync(копия, текст, 'utf8');
  console.log('сломанная копия: ' + копия);
  return копия;
}

/* Подмены. Хаб подкладываем в кэш require до загрузки дашборда, чтобы
   настоящий штаб/вм.js (и его ключ) вообще не открывался. */
const счётчикХаба = { вызовов: 0, поведение: null };

function подложитьХаб() {
  const путь = path.join(КОРЕНЬ, 'штаб', 'вм.js');
  const ключКэша = require.resolve(путь);
  require.cache[ключКэша] = {
    id: ключКэша, filename: ключКэша, loaded: true, children: [], paths: [],
    exports: {
      выполнитьСкрипт: function () {
        счётчикХаба.вызовов++;
        return счётчикХаба.поведение();
      }
    }
  };
}

/** Запрос к местному серверу комнат не уходит в сеть: сразу «соединение отказало». */
function заглушитьМестныйСервер() {
  const настоящий = http.get;
  http.get = function () {
    const { EventEmitter } = require('events');
    const запрос = new EventEmitter();
    запрос.destroy = function () {};
    setImmediate(function () { запрос.emit('error', new Error('заглушка: сети нет')); });
    return запрос;
  };
  return function вернуть() { http.get = настоящий; };
}

/** Один заход по http на локальный сервер дашборда. Свой запрос идёт настоящим http.get. */
function зайти(порт, настоящийGet) {
  return new Promise(function (готово, сбой) {
    настоящийGet('http://127.0.0.1:' + порт + '/' + encodeURI('онлайн'), function (ответ) {
      let тело = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (к) { тело += к; });
      ответ.on('end', function () { готово({ код: ответ.statusCode, тело: тело }); });
    }).on('error', сбой);
  });
}

function поднять(дашборд, порт0) {
  return new Promise(function (готово) {
    const сервер = дашборд.запуститьДашборд(порт0, { безПересборки: true });
    if (сервер.listening) { готово(сервер); return; }
    сервер.on('listening', function () { готово(сервер); });
  });
}

async function главное() {
  const путь = путьКДашборду();
  console.log('проверяю: ' + путь);

  подложитьХаб();
  const настоящийGet = http.get;
  const вернутьGet = заглушитьМестныйСервер();

  const онлайн = require(path.join(КОРЕНЬ, 'штаб', 'онлайн-страница.js'));
  // Чтобы загрузка дашборда не спрашивала настоящий 8790 через переменную окружения.
  delete process.env[онлайн.ИМЯ_ПЕРЕМЕННОЙ_ПОРТА];

  const дашборд = require(путь);
  проверить('дашборд подключается без запуска сервера, отдаёт запуститьДашборд',
    typeof дашборд.запуститьДашборд === 'function');
  if (typeof дашборд.запуститьДашборд !== 'function') { вернутьGet(); return; }

  const журнал = [];
  const настоящийError = console.error;
  console.error = function () { журнал.push(Array.prototype.join.call(arguments, ' ')); };
  const настоящийLog = console.log;
  console.log = function () {};

  let итог = {};
  try {
    /* Сценарий 1: хаб отвечает (медленно). Прогрев должен позвать хаб ровно раз до захода. */
    онлайн.сброситьКэшВМ();
    счётчикХаба.вызовов = 0;
    let хабОтветил = false;
    счётчикХаба.поведение = function () {
      return пауза(ХАБ_ЗАДЕРЖКА_МС).then(function () {
        хабОтветил = true;
        return { вывод: 'ГОТОВО\n{"сейчас":[],"сегодня":[],"неделя":[]}' };
      });
    };
    const сервер1 = await поднять(дашборд, 0);
    await пауза(300);
    итог.вызововДоЗахода = счётчикХаба.вызовов;
    // Ждём, пока хаб ответит и кэш обновится (тик после ответа).
    const начало = Date.now();
    while (!хабОтветил && Date.now() - начало < 10000) await пауза(50);
    await пауза(200);
    итог.ответ = await зайти(сервер1.address().port, настоящийGet);
    итог.вызововПослеЗахода = счётчикХаба.вызовов;
    await new Promise(function (г) { сервер1.close(г); });

    /* Сценарий 2: хаб отказал при старте. Дашборд жив, заход отвечает. */
    онлайн.сброситьКэшВМ();
    счётчикХаба.вызовов = 0;
    счётчикХаба.поведение = function () { return Promise.reject(new Error('хаб упал')); };
    let упал2 = null;
    let сервер2 = null;
    try {
      сервер2 = await поднять(дашборд, 0);
      await пауза(300);
      итог.вызововПриОтказе = счётчикХаба.вызовов;
      итог.ответ2 =await зайти(сервер2.address().port, настоящийGet);
    } catch (сбой) {
      упал2 = сбой;
    }
    итог.упал2 = упал2;
    if (сервер2) await new Promise(function (г) { сервер2.close(г); });

    /* Сценарий 3: сама страница «Онлайн» бросает ошибку при прогреве — глотаем, пишем в журнал. */
    const настоящаяСтраница = онлайн.страница;
    журнал.length = 0;
    онлайн.страница = function () { return Promise.reject(new Error('страница упала')); };
    let упал3 = null;
    try {
      const сервер3 = await поднять(дашборд, 0);
      await пауза(200);
      await new Promise(function (г) { сервер3.close(г); });
    } catch (сбой) {
      упал3 = сбой;
    }
    онлайн.страница = настоящаяСтраница;
    итог.упал3 = упал3;
    итог.строкВЖурнале3 = журнал.filter(function (с) { return с.indexOf('прогрев') !== -1; }).length;
  } finally {
    console.error = настоящийError;
    console.log = настоящийLog;
    вернутьGet();
  }

  console.log('\nСценарий 1: хаб отвечает');
  проверить('(а) до захода хаб спрошен ровно один раз', итог.вызововДоЗахода === 1,
    'вызовов: ' + итог.вызововДоЗахода);
  проверить('(а) заход не породил второго запроса к хабу', итог.вызововПослеЗахода === 1,
    'вызовов: ' + итог.вызововПослеЗахода);
  проверить('(в) первый заход получил страницу с кодом 200', итог.ответ && итог.ответ.код === 200,
    итог.ответ ? 'код ' + итог.ответ.код : 'нет ответа');
  проверить('(в) в ответе есть данные («Сейчас онлайн»)',
    !!итог.ответ && итог.ответ.тело.indexOf('Сейчас онлайн') !== -1);
  проверить('(в) в ответе нет «спрашиваю боевую машину»',
    !!итог.ответ && итог.ответ.тело.indexOf('спрашиваю') === -1);

  console.log('\nСценарий 2: хаб отказал при старте');
  проверить('(б) дашборд не упал, заход отвечает', итог.упал2 === null && !!итог.ответ2 && итог.ответ2.код === 200,
    итог.упал2 ? String(итог.упал2.message) : '');
  проверить('(б) хаб при этом всё же спрошен при старте', итог.вызововПриОтказе === 1,
    'вызовов: ' + итог.вызововПриОтказе);

  console.log('\nСценарий 3: страница «Онлайн» бросила ошибку при прогреве');
  проверить('(б) старт не упал', итог.упал3 === null, итог.упал3 ? String(итог.упал3.message) : '');
  проверить('(б) в журнал ушла ровно одна строка про прогрев', итог.строкВЖурнале3 === 1,
    'строк: ' + итог.строкВЖурнале3);

  console.log('\nИтого проверок: ' + всего + ', провалов: ' + провалов);
  process.exit(провалов ? 1 : 0);
}

главное().catch(function (сбой) {
  console.log('ПРОВАЛ: проверка сама упала: ' + (сбой && сбой.stack ? сбой.stack : сбой));
  process.exit(1);
});
