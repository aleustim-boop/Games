/** Раздача файлов проекта на свободном порту; «подмены» — карта
 *  {url-путь: файл-на-диске} для ломающего запуска (на обычном запуске
 *  этой раздачи вообще нет — идём на уже поднятый внешний стенд). */
function поднятьРаздачу(подмены) {
  const карта = подмены || {};
  const сервер = http.createServer(function (запрос, ответ) {
    let путь = запрос.url.split('?')[0].split('#')[0];
    try { путь = decodeURIComponent(путь); } catch (ошибка) { /* оставим как есть */ }
    const файл = карта[путь] || path.join(КОРЕНЬ, путь === '/' ? 'шахматы.html' : путь.slice(1));
    fs.readFile(файл, function (беда, тело) {
      if (беда) { ответ.writeHead(404); ответ.end('нет такого файла'); return; }
      ответ.writeHead(200, { 'Content-Type': ТИПЫ[path.extname(файл).toLowerCase()] || 'text/plain' });
      ответ.end(тело);
    });
  });
  return new Promise((готово) => сервер.listen(0, '127.0.0.1', () => готово(сервер)));
}

/* ---------------------------------------------------------------------
   ЛОМАЮЩИЙ ЗАПУСК: готовим ДВЕ испорченные копии во временной папке —
   файлы проекта не трогаем и не откатываем, только читаем.
   --------------------------------------------------------------------- */
function приготовитьИспорченныеКопии() {
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'лобби-шахмат-сломать-'));

  // 1. Копия шахматы.html — у #экран-лобби отбираем id.
  const путьHtml = path.join(КОРЕНЬ, 'шахматы.html');
  const исходникHtml = fs.readFileSync(путьHtml, 'utf8');
  const цельHtml = '<section id="экран-лобби" class="экран">';
  if (!исходникHtml.includes(цельHtml)) {
    console.error('ломающий запуск сломался: в шахматы.html не нашёлся тег ' +
      '«' + цельHtml + '» — ноль замен, портить нечего (провал, а не пропуск)');
    process.exit(2);
  }
  const испорченныйHtml = исходникHtml.replace(цельHtml, '<section id="экран-лобби-сломан" class="экран">');
  const копияHtml = path.join(папка, 'шахматы.html');
  fs.writeFileSync(копияHtml, испорченныйHtml, 'utf8');

  // 2. Копия style.css — красим #приложение мимо переменной --сб-фон.
  const путьCss = path.join(КОРЕНЬ, 'style.css');
  const исходникCss = fs.readFileSync(путьCss, 'utf8');
  const испорченныйCss = исходникCss +
    '\n/* СЛОМАНО (ломающий запуск tests/лобби-шахмат.js): #приложение красим ' +
    'мимо --сб-фон */\n#приложение { background-color: rgb(255, 0, 0) !important; }\n';
  const копияCss = path.join(папка, 'style.css');
  fs.writeFileSync(копияCss, испорченныйCss, 'utf8');

  console.log('ломающий запуск: испорченные копии лежат в ' + папка);
  return { папка, копияHtml, копияCss };
}

/** Слушатели ошибок страницы — не считаем шум от заблокированных нами же запросов. */
function собратьОшибки(страница) {
  const ошибки = [];
  страница.on('pageerror', (о) => ошибки.push('исключение: ' + о.message));
  страница.on('console', (с) => {
    if (с.type() === 'error' && /Failed to load resource/.test(с.text())) return;
    if (с.type() === 'error') ошибки.push('консоль: ' + с.text());
  });
  return ошибки;
}

function отчётПоОшибкам(ошибки, слова) {
  return слова + (ошибки.length ? ' — а они есть: ' + ошибки.join(' | ') : '');
}

