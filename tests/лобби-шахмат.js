    проверить(послеВозврата.плашкаСкрыта && послеВозврата.доскаВидна,
      '«Вернуться к игре» прячет плашку и партию НЕ прерывает (доска осталась)');

    // Теперь по-настоящему завершаем: лист → «Завершить партию» → «Завершить»
