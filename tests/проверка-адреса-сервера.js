/* =====================================================================
   Почему «Создать игру» не выдаёт код: проверка трёх адресов сервера.

   Живой игрок пожаловался: «нажимаю создать игру, а он не создаёт код».
   Этот прогон повторяет ровно то, что делает игра в браузере, и говорит,
   что человек увидит на экране в каждом из трёх случаев:

     1) адрес по умолчанию http://127.0.0.1:8765 — там сидит ЧУЖАЯ
        программа от другого проекта (отвечает 404, но не наша);
     2) настоящий сервер комнат через туннель (https://…trycloudflare.com);
     3) заведомо пустой порт, где нет вообще ничего.

   И отдельно — самая частая беда: игра опубликована по https, а адрес
   сервера по умолчанию http. Такой запрос браузер не отправляет вовсе.

   Запуск:  node tests/проверка-адреса-сервера.js
   Можно передать свой туннель:
            node tests/проверка-адреса-сервера.js https://мой-туннель.example
   ===================================================================== */

'use strict';

const ТУННЕЛЬ = (process.argv[2] || 'https://johnny-dense-shield-enquiries.trycloudflare.com')
  .replace(/\/+$/, '');
const ПО_УМОЛЧАНИЮ = 'http://127.0.0.1:8765';   // так записано в js/сеть.js
const ПУСТОЙ_ПОРТ = 'http://127.0.0.1:8123';
const ОТКУДА_ИГРА = 'https://aleustim-boop.github.io';   // опубликованная страница

/* Это дословное повторение проверки из js/сеть.js (функция
   «почемуАдресНеПодходит»). Нужно, чтобы показать: в одном из случаев
   игра даже не пытается позвонить серверу — и правильно делает. */
function почемуАдресНеПодходит(адресСтраницы, адресСервера) {
  if (!/^https?:\/\//i.test(адресСервера)) return 'адрес не начинается с http:// или https://';
  if (/^https:/i.test(адресСтраницы) && /^http:\/\//i.test(адресСервера)) {
    return 'страница защищённая (https), а сервер обычный (http) — браузер такой запрос запрещает';
  }
  return null;
}

/** Один запрос к серверу — такой же, как делает игра: POST с JSON. */
async function позвонить(адрес, путь, тело, откуда) {
  const начало = Date.now();
  try {
    const ответ = await fetch(адрес + путь, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Origin': откуда },
      body: JSON.stringify(тело || {}),
      signal: AbortSignal.timeout(10000)
    });
    let данные = {};
    try { данные = await ответ.json(); } catch (сбой) { данные = {}; }
    return {
      получилось: true,
      номер: ответ.status,
      разрешение: ответ.headers.get('access-control-allow-origin'),
      данные: данные,
      мс: Date.now() - начало
    };
  } catch (сбой) {
    return { получилось: false, беда: String(сбой.message || сбой), мс: Date.now() - начало };
  }
}

/** Разрешение браузера: перед POST с JSON он сначала спрашивает OPTIONS. */
async function спроситьРазрешение(адрес, путь, откуда) {
  try {
    const ответ = await fetch(адрес + путь, {
      method: 'OPTIONS',
      headers: {
        'Origin': откуда,
        'Access-Control-Request-Method': 'POST',
        'Access-Control-Request-Headers': 'content-type'
      },
      signal: AbortSignal.timeout(10000)
    });
    return {
      получилось: true,
      номер: ответ.status,
      разрешение: ответ.headers.get('access-control-allow-origin'),
      можноЗаголовки: ответ.headers.get('access-control-allow-headers')
    };
  } catch (сбой) {
    return { получилось: false, беда: String(сбой.message || сбой) };
  }
}

/** Что увидит человек на экране — по правилам из js/сеть.js. */
function чтоУвидитЧеловек(разрешение, звонок) {
  if (!разрешение.получилось || !разрешение.разрешение) {
    // Браузер не пропустит ответ: для игры это выглядит как оборванная связь.
    return 'Сервер игры не отвечает. Проверьте, что он запущен и что адрес игры указан верно.';
  }
  if (!звонок.получилось) {
    return 'Сервер игры не отвечает. Проверьте, что он запущен и что адрес игры указан верно.';
  }
  if (звонок.номер >= 400 || !звонок.данные.код) {
    return (звонок.данные.ошибка || 'Сервер не смог создать игру.');
  }
  return 'КОД ИГРЫ: ' + звонок.данные.код;
}

const ПОЛОСА = '='.repeat(70);

async function проверитьАдрес(название, адресСервера, адресСтраницы) {
  console.log('\n' + ПОЛОСА);
  console.log(название);
  console.log('  страница: ' + адресСтраницы);
  console.log('  сервер:   ' + адресСервера);

  const беда = почемуАдресНеПодходит(адресСтраницы, адресСервера);
  if (беда) {
    console.log('  ЗАПРОСА НЕ БУДЕТ: ' + беда);
    console.log('  человек увидит: «Игра открыта по защищённому адресу (https), а сервер игры');
    console.log('                   вдвоём — по обычному (http)…» — и код не появится НИКОГДА.');
    return { название, итог: 'кода не будет (запрет браузера)' };
  }

  const разрешение = await спроситьРазрешение(адресСервера, '/создать', адресСтраницы);
  if (разрешение.получилось) {
    console.log('  спросили разрешение (OPTIONS): ответ ' + разрешение.номер +
                ', разрешено для «' + (разрешение.разрешение || 'НИКОГО') + '»');
  } else {
    console.log('  спросили разрешение (OPTIONS): не ответил — ' + разрешение.беда);
  }

  const звонок = await позвонить(адресСервера, '/создать', {}, адресСтраницы);
  if (звонок.получилось) {
    console.log('  сам запрос: ответ ' + звонок.номер + ' за ' + звонок.мс + ' мс, тело: ' +
                JSON.stringify(звонок.данные).slice(0, 120));
  } else {
    console.log('  сам запрос: не ответил за ' + звонок.мс + ' мс — ' + звонок.беда);
  }

  const надпись = чтоУвидитЧеловек(разрешение, звонок);
  console.log('  ЧЕЛОВЕК УВИДИТ: ' + надпись);

  // Если комнату всё-таки создали — сразу убираем её за собой.
  if (звонок.получилось && звонок.данные && звонок.данные.код && звонок.данные.пропуск) {
    await позвонить(адресСервера, '/выйти',
      { код: звонок.данные.код, пропуск: звонок.данные.пропуск }, адресСтраницы);
    console.log('  (комнату ' + звонок.данные.код + ' убрал за собой)');
  }
  return { название, итог: надпись };
}

async function главное() {
  console.log('Проверяю, почему кнопка «Создать игру» может не выдать код.');
  console.log('Туннель для проверки: ' + ТУННЕЛЬ);

  const итоги = [];

  // 1. Опубликованная игра БЕЗ хвостика ?сервер= — самый частый случай.
  итоги.push(await проверитьАдрес(
    '1. Опубликованная игра без хвостика ?сервер= (адрес сервера берётся по умолчанию)',
    ПО_УМОЛЧАНИЮ, ОТКУДА_ИГРА));

  // 2. Опубликованная игра С хвостиком — так и должно быть.
  итоги.push(await проверитьАдрес(
    '2. Опубликованная игра с хвостиком ?сервер=<туннель>',
    ТУННЕЛЬ, ОТКУДА_ИГРА));

  // 3. Игра на своём компьютере, адрес по умолчанию — а на 8765 чужая программа.
  итоги.push(await проверитьАдрес(
    '3. Игра со своего компьютера, адрес по умолчанию 8765 (там чужая программа)',
    ПО_УМОЛЧАНИЮ, 'http://127.0.0.1:8130'));

  // 4. Для сравнения: порт, где вообще ничего нет.
  итоги.push(await проверитьАдрес(
    '4. Для сравнения: пустой порт, где нет вообще ничего',
    ПУСТОЙ_ПОРТ, 'http://127.0.0.1:8130'));

  console.log('\n' + ПОЛОСА);
  console.log('КОРОТКО:');
  итоги.forEach(function (и) {
    console.log('  ' + и.название.split('.')[0] + ') ' + и.итог);
  });
  console.log(ПОЛОСА);
}

главное().catch(function (сбой) {
  console.error('Прогон сорвался:', сбой);
  process.exit(1);
});
