/* =====================================================================
   Проверка страницы шашек: связь с поддельным Telegram, рекорды
   и вёрстка на трёх вертикальных телефонах.

   Настоящего Telegram здесь нет, поэтому WebApp подделан: он записывает,
   что игра его позвала (ready, expand, стрелка «Назад»), и хранит
   «облако» в памяти — по тем же правилам, что и настоящее (только
   латинские ключи).

   Запуск (страничный сервер уже поднят, например tests/локальный-сервер.js):
       node tests/шашки-в-телеграме-и-вёрстка.js          порт 8080
       node tests/шашки-в-телеграме-и-вёрстка.js 8130     другой порт

   Стенд перенесён из временной папки разработчика шашек; подделка Telegram
   и поиск playwright — общие для всех стендов (tests/браузер-робот.js).
   ===================================================================== */

const { chromium, подготовитьПодделку } = require('./браузер-робот.js');

const ПОРТ = Number(process.argv[2]) || 8080;
const АДРЕС = 'http://127.0.0.1:' + ПОРТ + '/шашки.html';
const РАЗМЕРЫ = [
  { ширина: 320, высота: 568 },
  { ширина: 360, высота: 640 },
  { ширина: 390, высота: 844 }
];

let провалов = 0;
function проверить(условие, слова) {
  if (условие) {
    console.log('  ок   — ' + слова);
  } else {
    провалов++;
    console.log('  ПЛОХО— ' + слова);
  }
}

/* Поддельный Telegram — общий, из tests/поддельный-телеграм.js: он ведёт
   window.__дневник (ready, expand, стрелкаПоказана, события) и window.__облако. */

/** Что вылезло за края окна. Возвращает список имён. */
async function ктоВылез(страница) {
  return страница.evaluate(() => {
    const беда = [];
    const ширина = window.innerWidth;
    const высота = window.innerHeight;
    document.querySelectorAll('#приложение *').forEach((узел) => {
      const место = узел.getBoundingClientRect();
      if (место.width === 0 && место.height === 0) return;
      const видим = window.getComputedStyle(узел).visibility !== 'hidden';
      if (!видим) return;
      // Клетки доски и подписи внутри них не проверяем поимённо: они внутри доски
      if (узел.classList.contains('поле') || узел.classList.contains('фишка')) return;
      if (узел.className && String(узел.className).indexOf('метка-') === 0) return;
      // Строки внутри прокручиваемого списка проверять нельзя: те, до которых
      // ещё не долистали, честно лежат ниже окна и обрезаны самим списком.
      if (узел.closest('.таблица')) return;
      if (место.left < -0.5 || место.top < -0.5 ||
          место.right > ширина + 0.5 || место.bottom > высота + 0.5) {
        беда.push((узел.id || узел.className || узел.tagName) +
          ' [' + Math.round(место.left) + ',' + Math.round(место.top) + ' → ' +
          Math.round(место.right) + ',' + Math.round(место.bottom) + ']');
      }
    });
    return беда;
  });
}

async function размерыСтраницы(страница) {
  return страница.evaluate(() => ({
    прокруткаШирина: document.documentElement.scrollWidth,
    прокруткаВысота: document.documentElement.scrollHeight,
    окноШирина: window.innerWidth,
    окноВысота: window.innerHeight,
    доска: (() => {
      const у = document.getElementById('доска').getBoundingClientRect();
      return { ширина: Math.round(у.width), высота: Math.round(у.height) };
    })()
  }));
}

(async () => {
  const браузер = await chromium.launch();

  /* ---------------- 1. Внутри поддельного Telegram ---------------- */
  console.log('\n=== 1. Страница внутри Telegram (поддельного) ===');
  {
    const окно = await браузер.newContext({ viewport: { width: 390, height: 844 } });
    const страница = await окно.newPage();
    const ошибки = [];
    страница.on('pageerror', (о) => ошибки.push('исключение: ' + о.message));
    страница.on('console', (с) => {
      // Отказ загрузки — наших рук дело: настоящий скрипт Telegram мы не пускаем
      if (с.type() === 'error' && /Failed to load resource/.test(с.text())) return;
      if (с.type() === 'error') ошибки.push('консоль: ' + с.text());
    });
    /* Подделка ложится до скриптов страницы, а настоящий telegram-web-app.js
       не пускается: загрузившись, он затёр бы подделку собой. */
    await подготовитьПодделку(страница, { версия: '7.0' });
    await страница.goto(АДРЕС);
    await страница.waitForTimeout(400);

    const дневник = await страница.evaluate(() => ({
      ready: window.__дневник.ready,
      expand: window.__дневник.expand,
      стрелка: window.__дневник.стрелкаПоказана,
      слушателиНазад: (window.__дневник.события.backButtonClicked || []).length,
      фонТемы: getComputedStyle(document.documentElement).getPropertyValue('--tg-theme-bg-color').trim(),
      // Какой цвет подделка отдала игре — с ним и сравниваем, а не с числом из головы.
      фонПодделки: window.Telegram.WebApp.themeParams.bg_color,
      кнопкаНазадСкрыта: document.getElementById('кнопка-назад').classList.contains('скрыт')
    }));

    проверить(дневник.ready === 1, 'игра сказала Telegram «готово» (ready): ' + дневник.ready);
    проверить(дневник.expand === 1, 'игра раскрыла окно на весь экран (expand): ' + дневник.expand);
    проверить(дневник.стрелка === 1, 'системная стрелка «Назад» показана: ' + дневник.стрелка);
    проверить(дневник.слушателиНазад === 1, 'нажатие стрелки кто-то слушает: ' + дневник.слушателиНазад);
    проверить(дневник.фонТемы === дневник.фонПодделки,
      'цвет темы Telegram приехал в CSS: «' + дневник.фонТемы + '» (подделка дала «' + дневник.фонПодделки + '»)');
    проверить(дневник.кнопкаНазадСкрыта, 'своя кнопка «Назад» спрятана — двух стрелок нет');

    // Записываем несколько партий и смотрим, куда они легли
    const итог = await страница.evaluate(async () => {
      const шаги = [
        { исход: 'победа', уровень: 'сложный' },
        { исход: 'победа', уровень: 'сложный' },
        { исход: 'ничья', уровень: 'сложный' },
        { исход: 'победа', уровень: 'сложный' },
        { исход: 'поражение', уровень: 'сложный' },
        { исход: 'победа', уровень: 'лёгкий' }
      ];
      const подписи = [];
      for (const шаг of шаги) подписи.push(await window.ШашкиРекорды.записатьПартию(шаг));
      return { подписи: подписи, ключи: Object.keys(window.__облако) };
    });
    console.log('  подписи на плашке итога:');
    итог.подписи.forEach((п) => console.log('     · ' + п));
    console.log('  ключи в облаке: ' + итог.ключи.join(', '));
    проверить(итог.ключи.indexOf('records_shashki') >= 0, 'таблица рекордов шашек легла под свой ключ records_shashki');
    проверить(итог.ключи.indexOf('rating_shashki') >= 0, 'личный счёт шашек лёг под свой ключ rating_shashki');
    проверить(итог.ключи.indexOf('rating_durak') < 0 && итог.ключи.indexOf('records_durak') < 0,
      'записи дурака не тронуты');
    проверить(/^Побед подряд: 3/.test(итог.подписи[3]),
      'ничья серию не прервала: после неё третья победа подряд');
    проверить(/рекорд/.test(итог.подписи[1]), 'вторая победа подряд отмечена как рекорд');
    проверить(/Серия прервалась: было 3/.test(итог.подписи[4]), 'поражение обрывает серию и говорит об этом');
    проверить(/Побед подряд: 1\. Лучшая серия: 3/.test(итог.подписи[5]), 'новая серия помнит лучшую');

    // Таблица рекордов в облаке: одна строка «3 подряд» на сложном + строка «1» на лёгком
    const таблицаВОблаке = await страница.evaluate(() => JSON.parse(window.__облако.records_shashki).таблица
      .map((с) => с.очки + ' ' + с.сложность));
    console.log('  таблица в облаке: ' + таблицаВОблаке.join(' | '));
    проверить(таблицаВОблаке.length === 2 && таблицаВОблаке[0] === '3 сложный' && таблицаВОблаке[1] === '1 лёгкий',
      'серия из трёх побед заняла одну строку, а не три ступеньки');

    // Стрелка «Назад»: сначала закрывает рекорды, потом уводит на index.html
    await страница.evaluate(() => window.ШашкиРекорды.показать());
    await страница.waitForTimeout(300);
    const рекордыВидны = await страница.evaluate(() => window.ШашкиРекорды.открыты());
    проверить(рекордыВидны, 'экран рекордов открылся');

    await страница.evaluate(() => window.__дневник.события.backButtonClicked[0]());
    const рекордыЗакрылись = await страница.evaluate(() => !window.ШашкиРекорды.открыты());
    проверить(рекордыЗакрылись, 'первое нажатие стрелки закрыло рекорды, а не увело со страницы');

    await страница.evaluate(() => window.__дневник.события.backButtonClicked[0]());
    await страница.waitForTimeout(500);
    проверить(/index\.html$/.test(страница.url()), 'второе нажатие увело на index.html: ' + страница.url());

    проверить(ошибки.length === 0, 'красных ошибок в консоли нет' +
      (ошибки.length ? ' — а они есть: ' + ошибки.join(' | ') : ''));
    await окно.close();
  }

  /* ---------------- 2. Вёрстка на трёх телефонах ---------------- */
  for (const размер of РАЗМЕРЫ) {
    console.log('\n=== 2. Вёрстка ' + размер.ширина + '×' + размер.высота + ' (без Telegram) ===');
    const окно = await браузер.newContext({
      viewport: { width: размер.ширина, height: размер.высота },
      isMobile: true, hasTouch: true, deviceScaleFactor: 2
    });
    const страница = await окно.newPage();
    const ошибки = [];
    страница.on('pageerror', (о) => ошибки.push('исключение: ' + о.message));
    страница.on('console', (с) => { if (с.type() === 'error') ошибки.push('консоль: ' + с.text()); });
    await страница.goto(АДРЕС);
    await страница.waitForTimeout(300);

    const мера = await размерыСтраницы(страница);
    console.log('  доска ' + мера.доска.ширина + '×' + мера.доска.высота +
      ', прокрутка ' + мера.прокруткаШирина + '×' + мера.прокруткаВысота +
      ' при окне ' + мера.окноШирина + '×' + мера.окноВысота);
    проверить(мера.прокруткаШирина <= мера.окноШирина + 1, 'по ширине ничего не выезжает');
    проверить(мера.прокруткаВысота <= мера.окноВысота + 1, 'по высоте ничего не выезжает');
    проверить(мера.доска.ширина > 200, 'доска не съёжилась: ' + мера.доска.ширина + ' точек');

    let вылезли = await ктоВылез(страница);
    проверить(вылезли.length === 0, 'на экране доски все части внутри окна' +
      (вылезли.length ? ': ' + вылезли.join('; ') : ''));

    const кнопки = await страница.evaluate(() => {
      const имена = ['кнопка-с-ботом', 'кнопка-вдвоём', 'кнопка-как-играть', 'кнопка-рекорды', 'кнопка-назад'];
      return имена.map((имя) => {
        const у = document.getElementById(имя).getBoundingClientRect();
        return имя + ' ' + Math.round(у.width) + '×' + Math.round(у.height);
      });
    });
    console.log('  кнопки под доской: ' + кнопки.join(', '));
    const низкие = await страница.evaluate(() => {
      const имена = ['кнопка-с-ботом', 'кнопка-вдвоём', 'кнопка-как-играть', 'кнопка-рекорды', 'кнопка-назад'];
      return имена.filter((имя) => document.getElementById(имя).getBoundingClientRect().height < 44);
    });
    проверить(низкие.length === 0, 'все кнопки не ниже 44 точек — попадёт палец' +
      (низкие.length ? ' (мелкие: ' + низкие.join(', ') + ')' : ''));

    // Экран рекордов с полной таблицей
    await страница.evaluate(async () => {
      const шаги = [
        ['победа', 'лёгкий'], ['победа', 'лёгкий'], ['победа', 'лёгкий'],
        ['победа', 'обычный'], ['поражение', 'обычный'], ['ничья', 'сложный'],
        ['победа', 'сложный'], ['победа', 'сложный'], ['поражение', 'лёгкий'],
        ['победа', 'обычный'], ['победа', 'обычный'], ['поражение', 'сложный']
      ];
      for (const [исход, уровень] of шаги) {
        await window.ШашкиРекорды.записатьПартию({ исход: исход, уровень: уровень });
      }
      window.ШашкиРекорды.показать();
    });
    await страница.waitForTimeout(300);

    const рекорды = await страница.evaluate(() => {
      const таблица = document.getElementById('таблица-рекордов');
      return {
        подпись: document.getElementById('лучший-рекорд').textContent,
        строк: таблица.querySelectorAll('.таблица__строка').length,
        разделов: таблица.querySelectorAll('.таблица__раздел').length,
        первые: Array.from(таблица.querySelectorAll('.таблица__строка')).slice(0, 4)
          .map((с) => Array.from(с.children).map((я) => я.textContent).filter(Boolean).join(' | ')),
        прокрутка: таблица.scrollHeight > таблица.clientHeight
      };
    });
    console.log('  «' + рекорды.подпись + '»');
    console.log('  строк ' + рекорды.строк + ', разделов ' + рекорды.разделов +
      (рекорды.прокрутка ? ', список прокручивается' : ''));
    рекорды.первые.forEach((с) => console.log('     · ' + с));
    проверить(рекорды.строк >= 10, 'в таблице не меньше десяти строк: ' + рекорды.строк);

    // Обрезанная многоточием ячейка — это потерянное число побед
    const обрезки = await страница.evaluate(() => {
      const беда = [];
      document.querySelectorAll('#таблица-рекордов .таблица__строка span').forEach((я) => {
        if (я.scrollWidth > я.clientWidth + 1) беда.push('«' + я.textContent + '»');
      });
      return беда;
    });
    проверить(обрезки.length === 0, 'ни одна подпись в таблице не обрезана' +
      (обрезки.length ? ': ' + обрезки.join(', ') : ''));

    вылезли = await ктоВылез(страница);
    проверить(вылезли.length === 0, 'на экране рекордов все части внутри окна' +
      (вылезли.length ? ': ' + вылезли.join('; ') : ''));

    const мера2 = await размерыСтраницы(страница);
    проверить(мера2.прокруткаВысота <= мера2.окноВысота + 1,
      'экран рекордов не тянет страницу вниз: ' + мера2.прокруткаВысота + ' при ' + мера2.окноВысота);

    проверить(ошибки.length === 0, 'красных ошибок в консоли нет' +
      (ошибки.length ? ' — а они есть: ' + ошибки.join(' | ') : ''));
    await окно.close();
  }

  await браузер.close();
  console.log('\n' + (провалов === 0 ? 'ВСЁ ЗЕЛЁНОЕ' : 'ПРОВАЛОВ: ' + провалов));
  process.exit(провалов === 0 ? 0 : 1);
})().catch((ошибка) => { console.error('проверка сломалась:', ошибка); process.exit(2); });
