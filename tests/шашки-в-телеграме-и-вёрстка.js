/** Что вылезло за края окна. Возвращает список имён.
 *  По ГОРИЗОНТАЛИ судим строго везде: вбок прокрутки нигде нет.
 *  По ВЕРТИКАЛИ строго судим все экраны, КРОМЕ содержимого #экран-шашек:
 *  у него теперь своя прокрутка (overflow-y: auto), и то, что не влезло
 *  по высоте, уезжает под неё, а не «ломает» раскладку — это не беда,
 *  а задуманное поведение (см. правку в шапке файла). Достижимость
 *  такой прокруткой проверяет отдельная функция достижимыЧастиПрокруткой. */
async function ктоВылез(страница) {
  return страница.evaluate(() => {
    const беда = [];
    const ширина = window.innerWidth;
    const высота = window.innerHeight;
    const экранШашек = document.getElementById('экран-шашек');
    document.querySelectorAll('#приложение *').forEach((узел) => {
      const место = узел.getBoundingClientRect();
      if (место.width === 0 && место.height === 0) return;
      const видим = window.getComputedStyle(узел).visibility !== 'hidden';
      if (!видим) return;
      // Клетки доски и подписи внутри них не проверяем поимённо: они внутри доски
      if (узел.classList.contains('поле') || узел.classList.contains('фишка')) return;
      if (узел.className && String(узел.className).indexOf('метка-') === 0) return;
      // Строки внутри прокручиваемого списка проверять нельзя: те, до которых
      // ещё не долистали, честно лежат ниже окна и обрезаны самим списком.
      if (узел.closest('.таблица')) return;
      const внутриПрокруткиШашек = !!(экранШашек && экранШашек.contains(узел));
      const горизонтальнаяБеда = место.left < -0.5 || место.right > ширина + 0.5;
      const вертикальнаяБеда = !внутриПрокруткиШашек && (место.top < -0.5 || место.bottom > высота + 0.5);
      if (горизонтальнаяБеда || вертикальнаяБеда) {
        беда.push((узел.id || узел.className || узел.tagName) +
          ' [' + Math.round(место.left) + ',' + Math.round(место.top) + ' → ' +
          Math.round(место.right) + ',' + Math.round(место.bottom) + ']' +
          (внутриПрокруткиШашек ? ' (по ширине, внутри #экран-шашек)' : ''));
      }
    });
    return беда;
  });
}

/** Части экрана партии, которые обязаны быть ДОСТИЖИМЫ прокруткой
 *  внутри #экран-шашек, даже когда сами по себе сейчас ниже окна:
 *  панели игроков, доска, строка хода, ряд кнопок партии. Для каждой —
 *  scrollIntoView и проверка «после прокрутки видна и не шире окна». */
async function достижимыЧастиПрокруткой(страница) {
  const ЧАСТИ = [
    { имя: 'панель-сверху', выбор: '#панель-сверху' },
    { имя: 'доска (рамка)', выбор: '.доска-шашек-рамка' },
    { имя: 'панель-снизу', выбор: '#панель-снизу' },
    { имя: 'строка-хода', выбор: '#строка-хода' },
    { имя: 'ряд кнопок партии', выбор: '.панель-доски' }
  ];
  const итог = [];
  for (const часть of ЧАСТИ) {
    const данные = await страница.evaluate((выбор) => {
      const экран = document.getElementById('экран-шашек');
      const узел = document.querySelector(выбор);
      if (!узел || !экран) return { есть: false };
      узел.scrollIntoView({ block: 'nearest', inline: 'nearest' });
      const р = узел.getBoundingClientRect();
      return {
        есть: true,
        видима: р.height > 0 && р.top >= -0.5 && р.bottom <= window.innerHeight + 0.5,
        шире: р.left < -0.5 || р.right > window.innerWidth + 0.5,
        место: Math.round(р.top) + '→' + Math.round(р.bottom)
      };
    }, часть.выбор);
    итог.push(Object.assign({ имя: часть.имя }, данные));
  }
  return итог;
}

async function размерыСтраницы(страница) {
  return страница.evaluate(() => ({
    прокруткаШирина: document.documentElement.scrollWidth,
    прокруткаВысота: document.documentElement.scrollHeight,
    окноШирина: window.innerWidth,
    окноВысота: window.innerHeight,
    доска: (() => {
      const у = document.getElementById('доска').getBoundingClientRect();
      return { ширина: Math.round(у.width), высота: Math.round(у.height) };
    })()
  }));
}

