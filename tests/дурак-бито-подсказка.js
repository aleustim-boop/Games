/* =====================================================================
   ДУРАК: «БИТО» ПОДСВЕЧЕНО, КОГДА СТОЛ ЖДЁТ ТОЛЬКО ЕГО (игры/дурак/game.js, style.css).

   Беда: со временем на ход человек «засыпает» после двух просрочек подряд.
   Новичок не понимает, что стол стоит из-за его нажатия «Бито», и пропускает
   два таких момента. Теперь, пока идёт отсчёт, слово у человека, а подкинуть
   нечем, кнопка завершения получает класс «кнопка--ждут», а в строке подсказки
   стоит «Нажмите «Бито» — ход ждёт вас».

   Проверяем:
     а) отсчёт идёт, ждут только «Бито» — класс и слова есть;
     б) есть чем подкинуть — класса и слов нет;
     в) после нажатия «Бито» класс и слова сняты;
     г) без времени на ход — класса и слов нет;
     д) правило класса есть в style.css (и не мигает чаще раза в секунду,
        и гасится при «уменьшить анимацию»).

   Как проверяет. Поднимает НАСТОЯЩИЙ игры/дурак/game.js в песочнице vm (документ —
   из tests/поддельный-браузер.js), собирает стол и зовёт
   рисоватьПодсказкуИКнопки().

   Запуск:
       node tests/дурак-бито-подсказка.js            — обычный прогон
       node tests/дурак-бито-подсказка.js --сломать <папка>
         — портит КОПИИ игры/дурак/game.js и style.css в указанной папке (она
         создаётся, если её нет); каждая порча обязана покраснеть; образец
         порчи ищется в файле ровно один раз (ноль или два — провал).
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { сделатьДокумент } = require('./поддельный-браузер');

const КОРЕНЬ = path.join(__dirname, '..');
const ПУТЬ_GAME = path.join(КОРЕНЬ, 'игры', 'дурак', 'game.js');
const ПУТЬ_CSS = path.join(КОРЕНЬ, 'общее/css/style.css');

const ПРОЧТЕНИЕ = 'Нажмите «Бито» — ход ждёт вас';

/** Поднять game.js в песочнице; вернуть «спросить» (выражение внутри песочницы). */
function поднятьИгру(путьGameJs) {
  const документ = сделатьДокумент();
  const оригинал = документ.getElementById;
  const пустышки = new Map();
  // Незнакомый id — честная пустышка, а не null: game.js трогает сотни узлов разметки.
  документ.getElementById = function (id) {
    const найден = оригинал(id);
    if (найден) return найден;
    if (!пустышки.has(id)) { const у = документ.createElement('div'); у.id = id; пустышки.set(id, у); }
    return пустышки.get(id);
  };
  const окно = {
    document: документ,
    addEventListener: function () {}, removeEventListener: function () {},
    matchMedia: function () { return { matches: false, addEventListener: function () {}, addListener: function () {} }; },
    localStorage: { getItem: function () { return null; }, setItem: function () {}, removeItem: function () {} },
    innerWidth: 390, innerHeight: 844,
    requestAnimationFrame: function (ф) { return setTimeout(ф, 0); },
    cancelAnimationFrame: function (id) { clearTimeout(id); },
    getComputedStyle: function () { return { fontSize: '16px', lineHeight: '19.2px', getPropertyValue: function () { return ''; } }; },
    ЛистЕщё: { подключить: function () {
      return { открыть: function () {}, закрыть: function () {}, открыт: function () { return false; },
        освежитьКнопкуНастроек: function () {}, спроситьЗавершить: function () { return false; } };
    } }
  };
  const песочница = {
    window: окно, document: документ, localStorage: окно.localStorage,
    navigator: { userAgent: 'тест дурак-бито-подсказка' },
    console: { log: function () {}, info: function () {}, warn: function () {}, error: function () {} },
    setTimeout: setTimeout, clearTimeout: clearTimeout, setInterval: setInterval, clearInterval: clearInterval,
    Math: Math, Date: Date, JSON: JSON, Number: Number, String: String, Array: Array, Object: Object,
    Boolean: Boolean, RegExp: RegExp, Error: Error, isFinite: isFinite, isNaN: isNaN,
    parseInt: parseInt, parseFloat: parseFloat, Map: Map, Set: Set,
    requestAnimationFrame: окно.requestAnimationFrame, cancelAnimationFrame: окно.cancelAnimationFrame,
    getComputedStyle: окно.getComputedStyle
  };
  песочница.globalThis = песочница;
  vm.createContext(песочница);
  vm.runInContext(fs.readFileSync(путьGameJs, 'utf8'), песочница, { filename: путьGameJs + ' (дурак-бито-подсказка)' });
  return function (выражение) { return vm.runInContext(выражение, песочница); };
}

/**
 * Собрать стол вдвоём: подход отбит, слово у человека. Рука: «нечем» —
 * одна карта, которой подкидывать нельзя; «есть» — карта того же достоинства,
 * что лежит на столе. Дальше рисуем и сообщаем, что видно на экране.
 * Возвращает JSON: { класс, слова } — и после нажатия «Бито», если просили.
 */
function показ(спросить, добавки) {
  const код =
    '(function () {' +
    '  const д = ' + JSON.stringify(добавки) + ';' +
    "  режим = РЕЖИМ_БОТ;" +
    '  партия = создатьПартию({ сложность: "лёгкая", игроков: 2, лимитСекундНаХод: д.лимит });' +
    '  const м = МАСТИ;' +
    '  const к = function (масть, имя) { return { масть: масть, имя: имя, вес: ВСЕ_ДОСТОИНСТВА.indexOf(имя) + 2 }; };' +
    '  партия.козырь = м[1];' +
    '  партия.атакует = "человек";' +
    '  партия.стол = [{ атака: к(м[0], "6"), защита: к(м[1], "7") }];' +
    '  партия.берёт = false; партия.пасы = [];' +
    '  партия.руки.человек = [д.естьЧем ? к(м[2], "6") : к(м[2], "10")];' +
    '  партия.началоХода = Date.now();' +
    '  картаДляБроска = null;' +
    '  const кнопка = document.getElementById("кнопка-завершить");' +
    '  const снять = function () {' +
    '    return { класс: кнопка.classList.contains("кнопка--ждут"), слова: текстДействия() };' +
    '  };' +
    '  рисоватьПодсказкуИКнопки();' +
    '  const до = снять();' +
    '  let после = null;' +
    '  if (д.нажать) { нажатьБито(); рисоватьПодсказкуИКнопки(); после = снять(); }' +
    '  if (typeof остановитьТаймерПросрочкиХода === "function") остановитьТаймерПросрочкиХода();' +
    '  if (таймер !== null) { clearTimeout(таймер); таймер = null; }' +
    '  return JSON.stringify({ до: до, после: после, фаза: фаза(партия) });' +
    '})()';
  return JSON.parse(спросить(код));
}

function прогнатьСтол(путьGameJs, путьCss) {
  const строки = [];
  let провалов = 0;
  function проверить(имя, условие, подробности) {
    if (условие) { строки.push('OK    ' + имя); return; }
    провалов++;
    строки.push('ПЛОХО ' + имя + (подробности ? ' — ' + подробности : ''));
  }
  const текст = function (о) { return JSON.stringify(о); };

  let спросить = null;
  try {
    спросить = поднятьИгру(путьGameJs);
    проверить('0) игры/дурак/game.js поднимается в песочнице', true);
  } catch (сбой) {
    проверить('0) игры/дурак/game.js поднимается в песочнице', false, сбой.message);
    return { строки: строки, провалов: провалов };
  }
  function безСбоя(добавки) {
    try { return показ(спросить, добавки); } catch (сбой) { return { ошибка: сбой.message }; }
  }

  const ждут = безСбоя({ лимит: 30, естьЧем: false });
  проверить('а0) стол собран: фаза «подкидывание»', ждут.фаза === 'подкидывание', текст(ждут));
  проверить('а1) отсчёт идёт, подкинуть нечем: у кнопки класс «кнопка--ждут»',
    Boolean(ждут.до) && ждут.до.класс === true, текст(ждут));
  проверить('а2) слова «' + ПРОЧТЕНИЕ + '»',
    Boolean(ждут.до) && ждут.до.слова === ПРОЧТЕНИЕ, текст(ждут));

  const есть = безСбоя({ лимит: 30, естьЧем: true });
  проверить('б1) есть чем подкинуть: класса нет',
    Boolean(есть.до) && есть.до.класс === false, текст(есть));
  проверить('б2) есть чем подкинуть: слов «ход ждёт вас» нет',
    Boolean(есть.до) && typeof есть.до.слова === 'string' && есть.до.слова.indexOf('ход ждёт вас') === -1 && есть.до.слова !== '',
    текст(есть));

  const нажали = безСбоя({ лимит: 30, естьЧем: false, нажать: true });
  проверить('в1) до нажатия класс был (проверка не пустая)',
    Boolean(нажали.до) && нажали.до.класс === true, текст(нажали));
  проверить('в2) после «Бито» класс снят',
    Boolean(нажали.после) && нажали.после.класс === false, текст(нажали));
  проверить('в3) после «Бито» слов «ход ждёт вас» нет',
    Boolean(нажали.после) && typeof нажали.после.слова === 'string' && нажали.после.слова.indexOf('ход ждёт вас') === -1,
    текст(нажали));

  const безВремени = безСбоя({ лимит: 0, естьЧем: false });
  проверить('г1) без времени на ход: класса нет',
    Boolean(безВремени.до) && безВремени.до.класс === false, текст(безВремени));
  проверить('г2) без времени на ход: слова прежние «Подкинуть нечем — нажмите «Бито»»',
    // перед тире в игре стоит неразрывный пробел ( )
    Boolean(безВремени.до) && безВремени.до.слова === 'Подкинуть нечем — нажмите «Бито»', текст(безВремени));

  // д) правило в style.css
  const css = fs.readFileSync(путьCss, 'utf8');
  const правило = /#панель-кнопок\s*>\s*\.кнопка\.кнопка--ждут\s*\{([^}]*)\}/.exec(css);
  проверить('д1) в style.css есть правило «.кнопка.кнопка--ждут»', Boolean(правило));
  const тело = правило ? правило[1] : '';
  const период = /animation:[^;]*?(\d+(?:\.\d+)?)s/.exec(тело);
  проверить('д2) подсветка дышит не чаще раза в секунду (период ≥ 1 с)',
    Boolean(период) && parseFloat(период[1]) >= 1, период ? период[0] : 'animation не найден');
  проверить('д3) подсветка берёт салатовый акцент из переменной',
    тело.indexOf('var(--сб-акцент)') !== -1);
  проверить('д4) при «уменьшить анимацию» движение выключено',
    /prefers-reduced-motion:\s*reduce\)\s*\{\s*#экран-игры #панель-кнопок > \.кнопка\.кнопка--ждут\s*\{\s*animation:\s*none/.test(css));

  return { строки: строки, провалов: провалов };
}

