function сколькоВхождений(текст, образец) {
  return текст.split(образец).length - 1;
}

function ломающийЗапуск(папка) {
  fs.mkdirSync(папка, { recursive: true });
  const игра = fs.readFileSync(ПУТЬ_GAME, 'utf8');
  const стиль = fs.readFileSync(ПУТЬ_CSS, 'utf8');
  // В файлах могут быть переводы строки Windows: подгоняем образцы под них.
  const пс = function (текст, ПС) { return текст.replace(/\n/g, ПС); };
  const строки = [];
  let провалов = 0;
  ПОРЧИ.forEach(function (порча, номер) {
    const исходник = порча.файл === 'game' ? игра : стиль;
    const ПС = исходник.indexOf('\r\n') !== -1 ? '\r\n' : '\n';
    const образец = пс(порча.образец, ПС);
    const замена = пс(порча.замена, ПС);
    const раз = сколькоВхождений(исходник, образец);
    if (раз !== 1) {
      провалов++;
      строки.push('ПЛОХО порча «' + порча.имя + '»: образец найден ' + раз + ' раз (нужно ровно 1)');
      return;
    }
    const испорченный = исходник.replace(образец, function () { return замена; });
    const копияИгры = path.join(папка, 'game-' + номер + '.js');
    const копияСтиля = path.join(папка, 'style-' + номер + '.css');
    fs.writeFileSync(копияИгры, порча.файл === 'game' ? испорченный : игра);
    fs.writeFileSync(копияСтиля, порча.файл === 'css' ? испорченный : стиль);
    const итог = прогнатьСтол(копияИгры, копияСтиля);
    if (итог.провалов > 0) {
      строки.push('OK    порча «' + порча.имя + '» покраснела (провалов: ' + итог.провалов + ')');
    } else {
      провалов++;
      строки.push('ПЛОХО порча «' + порча.имя + '» НЕ покраснела — проверка слепая');
    }
  });
  return { строки: строки, провалов: провалов, всего: ПОРЧИ.length };
}

const позиция = process.argv.indexOf('--сломать');
if (позиция !== -1) {
  const папка = process.argv[позиция + 1];
  if (!папка) {
    console.log('Нужна папка для копий: node tests/дурак-бито-подсказка.js --сломать <папка>');
    process.exit(2);
  }
  console.log('=== Дурак: подсветка «Бито» — ломающий запуск (порча копий в ' + папка + ') ===\n');
  const р = ломающийЗапуск(папка);
  р.строки.forEach(function (с) { console.log(с); });
  console.log('');
  console.log('Итого проверок: ' + р.всего + ', провалов: ' + р.провалов);
  process.exitCode = р.провалов ? 1 : 0;
} else {
  console.log('=== Дурак: подсветка «Бито», когда ждут только её (файл: ' + ПУТЬ_GAME + ') ===\n');
  const р = прогнатьСтол(ПУТЬ_GAME, ПУТЬ_CSS);
  р.строки.forEach(function (с) { console.log(с); });
  console.log('');
  console.log('Итого проверок: ' + р.строки.length + ', провалов: ' + р.провалов);
  process.exitCode = р.провалов ? 1 : 0;
}
