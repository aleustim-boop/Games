/** Значение вида const ИМЯ = 'текст'; — как оно записано в файле сервера. */
function константаСервера(имя) {
  const совпадение = ТЕКСТ_СЕРВЕРА.match(new RegExp('const\\s+' + имя + '\\s*=\\s*\'((?:[^\'\\\\]|\\\\.)*)\''));
  if (!совпадение) throw new Error('в ' + ПУТЬ_СЕРВЕРА + ' не нашлась константа ' + имя);
  return совпадение[1];
}

/** Настоящее тело function ИМЯ(...) {...} из файла сервера — как исполняемая функция. */
function функцияСервера(имя) {
  const метка = 'function ' + имя + '(';
  const начало = ТЕКСТ_СЕРВЕРА.indexOf(метка);
  if (начало === -1) throw new Error('в ' + ПУТЬ_СЕРВЕРА + ' не нашлась функция ' + имя);
  const закрывающаяСкобка = ТЕКСТ_СЕРВЕРА.indexOf(')', начало);
  const параметры = ТЕКСТ_СЕРВЕРА.slice(начало + метка.length, закрывающаяСкобка);
  const телоНачало = ТЕКСТ_СЕРВЕРА.indexOf('{', закрывающаяСкобка);
  let глубина = 0, конец = телоНачало;
  for (; конец < ТЕКСТ_СЕРВЕРА.length; конец++) {
    if (ТЕКСТ_СЕРВЕРА[конец] === '{') глубина++;
    else if (ТЕКСТ_СЕРВЕРА[конец] === '}') { глубина--; if (глубина === 0) break; }
  }
  // eslint-disable-next-line no-new-func
  return new Function(параметры, ТЕКСТ_СЕРВЕРА.slice(телоНачало + 1, конец));
}

