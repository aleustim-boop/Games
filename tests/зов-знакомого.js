/** Ловит console.error за время деяния — для проверки строки журнала беды письма. */
async function споймайЖурнал(деяние) {
  const исходный = console.error;
  const строки = [];
  console.error = function () { строки.push(Array.prototype.slice.call(arguments).join(' ')); };
  let результат;
  try {
    результат = await деяние();
  } finally {
    console.error = исходный;
  }
  return { результат: результат, строки: строки };
}

