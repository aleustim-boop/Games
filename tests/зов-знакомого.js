/* ---------------------------------------------------------------------
   Подпись Telegram — по тому же правилу, что у сервера
   --------------------------------------------------------------------- */

function подписать(поля, токен) {
  const строки = Object.keys(поля)
    .filter(function (к) { return к !== 'hash'; })
    .map(function (к) { return к + '=' + поля[к]; })
    .sort();
  const ключ = crypto.createHmac('sha256', 'WebAppData').update(токен).digest();
  return crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');
}

/** initData так, как её присылает настоящая страница Telegram. */
function подписьИгрока(номер, имя, токен) {
  const поля = {
    query_id: 'AAF' + номер,
    user: JSON.stringify({ id: номер, first_name: имя, username: 'igrok' + номер }),
    auth_date: String(Math.floor(Date.now() / 1000))
  };
  const сподписью = Object.assign({}, поля, { hash: подписать(поля, токен || ТОКЕН_ДЛЯ_ПРОБЫ) });
  return Object.keys(сподписью)
    .map(function (к) { return encodeURIComponent(к) + '=' + encodeURIComponent(сподписью[к]); })
    .join('&');
}

/* ---------------------------------------------------------------------
   Разговор с дверью
   --------------------------------------------------------------------- */

function спросить(путь, тело) {
  return new Promise(function (готово, беда) {
    const данные = Buffer.from(JSON.stringify(тело || {}), 'utf8');
    const запрос = http.request({
      host: ХОЗЯИН_АДРЕС, port: ПОРТ, path: encodeURI(путь), method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let текст = '';
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        let разобрано = null;
        try { разобрано = JSON.parse(текст || '{}'); } catch (сбой) { разобрано = null; }
        готово({ код: ответ.statusCode, тело: разобрано, текст: текст });
      });
    });
    запрос.on('error', беда);
    запрос.write(данные);
    запрос.end();
  });
}

/* ---------------------------------------------------------------------
   Настоящие столы для зовущих

   Дверь /позвать теперь сверяет код стола: жив ли он и сидит ли за ним
   зовущий. Без настоящей комнаты любой зов отклонится на этой проверке
   раньше, чем дойдёт до ключа знакомого, запрета или чужого бота, —
   и проверки перестанут проверять то, что заявлено в их названии.
   Поэтому каждому, кто в этом файле зовёт по-настоящему, заводим стол
   через ту же дверь /создать, что и обычная игра. Один игрок — один
   стол, повторно не создаём (см. кэш ниже). --------------------------- */

const столыИгроков = new Map();   // кто (номер) → { код, пропуск }

/** Настоящий стол этого игрока — создаёт при первом обращении, дальше отдаёт тот же. */
async function стол(кто, имя) {
  if (столыИгроков.has(кто)) return столыИгроков.get(кто);
  const ответ = await спросить('/создать', { initData: подписьИгрока(кто, имя) });
  const запись = {
    код: (ответ.тело && ответ.тело.код) || '',
    пропуск: (ответ.тело && ответ.тело.пропуск) || ''
  };
  столыИгроков.set(кто, запись);
  return запись;
}

/**
 * Позвать знакомого от имени этого игрока. По умолчанию — с его же
 * настоящего стола (создаст при первой нужде): так проверка стола не
 * мешает проверить то, что проверяется дальше. Четвёртым доводом можно
 * подменить что-то одно или сразу всё — { код, ссылка, метка } — для
 * проверок самого стола (чужой код, мёртвый код, чужой бот).
 */
async function позвать(кто, имя, ключ, свой) {
  const мойСтол = await стол(кто, имя);
  свой = свой || {};
  const код = свой.код !== undefined ? свой.код : мойСтол.код;
  const ссылка = свой.ссылка !== undefined ? свой.ссылка : ссылкаЗаСтол(мойСтол.код, свой.метка);
  const ответ = await спросить('/позвать', {
    initData: подписьИгрока(кто, имя),
    ключ: ключ,
    ссылка: ссылка,
    код: код
  });
  const итог = испортить(ответ.тело);
  итог._ссылка = ссылка;   // для проверок, что письмо ведёт ровно сюда
  return итог;
}

