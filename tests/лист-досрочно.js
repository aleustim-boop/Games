function ломать() {
  const исходник = fs.readFileSync(ФАЙЛ_ЛИСТА, 'utf8').replace(/\r\n/g, '\n');
  const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'лист-досрочно-лом-'));
  let провалов = 0;
  try {
    ПОРЧИ.forEach(function (порча, н) {
      const вхождений = исходник.split(порча.было).length - 1;
      if (вхождений !== 1) {
        провалов++;
        console.log('ПРОВАЛ порчи «' + порча.что + '»: образец найден ' + вхождений + ' раз (нужно ровно 1)');
        return;
      }
      const копия = path.join(папка, 'лист-ещё-' + н + '.js');
      fs.writeFileSync(копия, исходник.replace(порча.было, порча.стало), 'utf8');
      const прогон = spawnSync(process.execPath, [__filename, '--файл', копия], { encoding: 'utf8', timeout: 60000 });
      const красные = (прогон.stdout || '').split('\n').filter(function (с) { return с.indexOf('ПЛОХО [' + порча.метка + ']') === 0; });
      const ок = прогон.status === 1 && красные.length > 0;
      if (!ок) провалов++;
      console.log((ок ? 'ПОКРАСНЕЛА  ' : 'НЕ ПОКРАСНЕЛА ') + '[' + порча.метка + '] ' + порча.что +
        (ок ? ' — ' + красные[0].slice(0, 110) : ' (код ' + прогон.status + ')' + (прогон.stderr ? ' stderr: ' + прогон.stderr.slice(0, 200) : '')));
    });
  } finally {
    fs.rmSync(папка, { recursive: true, force: true });
  }
  console.log('\nИтого проверок: ' + ПОРЧИ.length + ', провалов: ' + провалов);
  process.exitCode = провалов ? 1 : 0;
}

if (process.argv.includes('--сломать')) {
  ломать();
} else {
  console.log('=== Голосование «закончить по согласию» в листе «⋯» (файл: ' + путьКФайлу + ') ===');
  прогнать().then(function (итог) {
    итог.строки.forEach(function (с) { console.log(с); });
    console.log('\nИтого проверок: ' + итог.строки.length + ', провалов: ' + итог.провалов);
    process.exitCode = итог.провалов ? 1 : 0;
  }, function (е) {
    console.log('ПЛОХО [запуск] проверка упала: ' + (е && е.stack || е));
    console.log('\nИтого проверок: 1, провалов: 1');
    process.exitCode = 1;
  });
}
