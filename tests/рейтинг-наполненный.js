'use strict';

/* =====================================================================
   РЕЙТИНГ ДУРАКА — ЖИВОЙ СТЕНД ДЛЯ ОФОРМИТЕЛЯ.

   Зачем. Экран рейтинга (эталон/дурак-06-рейтинг.png) сервер отдаёт
   ТОЛЬКО игроку, открывшему игру внутри Telegram: «иначе игрока не
   отличить от другого» — так честно отвечает дверь /рейтинг вне
   Telegram. Открыть игру внутри настоящего Telegram оформителю
   неоткуда, значит и посмотреть на наполненный экран ему неоткуда,
   если не подделать весь путь целиком.

   Этот стенд НЕ разовый прогон, а адрес, который остаётся жить, пока
   его не остановят (Ctrl+C) — открыть можно в обычном браузере хоть
   сто раз подряд. Поднимает два маленьких сервера:

     • ПОРТ_СТРАНИЦ — раздаёт файлы игры (index.html, style.css, js/…),
       как обычный сервер для локальной проверки, но вырезает настоящий
       telegram-web-app.js и вписывает вместо него подделку из
       tests/поддельный-телеграм.js — ту же, которой пользуются
       остальные стенды, — с готовой подписью Telegram;

     • ПОРТ_КОМНАТ — СВОЯ маленькая копия ровно одной двери, /рейтинг.
       Настоящую дверь (server/сервер.js) поднять здесь нельзя: она
       проверяет подпись Telegram настоящим токеном бота из bot/.env,
       а токен — секрет, который тестировщику трогать нельзя, и взяться
       ему тут неоткуда. Вместо криптографии копия просто читает НОМЕР
       игрока из той же поддельной подписи (это же не боевой сервер —
       проверять тут нечего и некого), а дальше зовёт НАСТОЯЩИЙ
       server/рейтинг.js — тот же модуль, что и боевой сервер: срез
       таблицы, очки, потолки и порядок мест не выдуманы, они настоящие.

   НАПОЛНЕНИЕ. Восемь игроков дурака с заведомо разными и убывающими
   очками: пятеро с очками больше моих (первая пятёрка лидеров), один
   с очками меньше — «Я» стою́ на седьмом месте из восьми, за пределами
   первой пятёрки, как и просил штаб (см. таблицу очков в «наполнить»).

   ДАННЫЕ ВЛАДЕЛЬЦА НЕ ТРОГАЮТСЯ. Папка рейтинга уведена в свою
   временную (переменная GAMES_DATA) и не записывается на диск вовсе:
   рейтинг.включитьЗапись() здесь ни разу не зовётся, вся память —
   только в этом процессе, и с его остановкой она исчезает.

   Запуск:
       node tests/рейтинг-наполненный.js               порты 8280 и 8281
       node tests/рейтинг-наполненный.js 8280 8281      те же явно
   Останов: Ctrl+C в этом окне.

   Порт 8790 (боевой сервер комнат) стенд трогать отказывается — см. проверку
   ниже.
   ===================================================================== */

const http = require('http');
const fs = require('fs');
const path = require('path');

const ПОРТ_СТРАНИЦ = Number(process.argv[2]) || 8280;
const ПОРТ_КОМНАТ = Number(process.argv[3]) || 8281;
const ХОСТ = '127.0.0.1';

if (ПОРТ_СТРАНИЦ === 8790 || ПОРТ_КОМНАТ === 8790) {
  console.error('Порт 8790 — боевой сервер комнат, стенду сюда нельзя. Выберите другой порт.');
  process.exit(1);
}

const КОРЕНЬ = path.resolve(path.join(__dirname, '..'));

/* Своя папка данных — ДО подключения серверных модулей: путь они читают
   при первом обращении, и подменять его позже уже поздно (проверено
   на tests/наполнить-таблицу-рейтинга.js и tests/список-знакомых-наполненный.js). */
const СВОЯ_ПАПКА = path.join(require('os').tmpdir(), 'рейтинг-стенд-' + Date.now());
process.env.GAMES_DATA = СВОЯ_ПАПКА;

const рейтинг = require(path.join(__dirname, '..', 'server', 'рейтинг.js'));
const { текстПодделки } = require('./поддельный-телеграм.js');

/* ---------------------------------------------------------------------
   1. Наполнение: восемь игроков, очки заведомо разные и убывающие
   --------------------------------------------------------------------- */

const Я = 910001;

const АЛЕКСЕЙ = { номер: 910002, имя: 'Алексей' };   // 1 место, 60 очков (потолок)
const МАРИЯ    = { номер: 910003, имя: 'Мария' };     // 2 место, 50 очков
const ДМИТРИЙ  = { номер: 910004, имя: 'Дмитрий' };   // 3 место, 40 очков
const ЕКАТЕРИНА = { номер: 910005, имя: 'Екатерина' }; // 4 место, 30 очков
const ИГОРЬ    = { номер: 910006, имя: 'Игорь' };     // 5 место, 20 очков
const ОЛЬГА    = { номер: 910007, имя: 'Ольга' };     // 6 место, 10 очков
const ПЁТР     = { номер: 910008, имя: 'Пётр' };      // 8 место, 0 очков
const ВЫ       = { номер: Я, имя: 'Иван Тестов' };    // 7 место, 5 очков — ЗА пределами топ-5

/** Партия двоих: victoria — победитель, loser — проигравший (или ничья). */
function партия(победитель, проигравший, ничья) {
  return [
    { номер: победитель.номер, имя: победитель.имя, победил: !ничья, ничья: Boolean(ничья) },
    { номер: проигравший.номер, имя: проигравший.имя, победил: false, ничья: Boolean(ничья) }
  ];
}

function наполнить() {
  /* Каждая пара встречается РОВНО ОДИН РАЗ — ограничитель сговора
     (не больше 5 партий с одним и тем же человеком в сутки) тут даже
     близко не задет, беспокоиться не о чем. Очки: победа над человеком
     даёт 10, ничья — 5, поражение — 0 (см. server/рейтинг.js, «ЦЕНА»). */
  [ПЁТР, ОЛЬГА, ИГОРЬ, ЕКАТЕРИНА, ДМИТРИЙ, МАРИЯ].forEach(function (проигравший) {
    рейтинг.учестьПартию('дурак', партия(АЛЕКСЕЙ, проигравший));   // Алексей: 6 побед = 60
  });
  рейтинг.учестьПартию('дурак', партия(ВЫ, АЛЕКСЕЙ, true));         // Я: ничья = 5 (Алексею уже некуда — потолок 60)
  [ПЁТР, ОЛЬГА, ИГОРЬ, ЕКАТЕРИНА, ДМИТРИЙ].forEach(function (проигравший) {
    рейтинг.учестьПартию('дурак', партия(МАРИЯ, проигравший));      // Мария: 5 побед = 50
  });
  [ПЁТР, ОЛЬГА, ИГОРЬ, ЕКАТЕРИНА].forEach(function (проигравший) {
    рейтинг.учестьПартию('дурак', партия(ДМИТРИЙ, проигравший));    // Дмитрий: 4 победы = 40
  });
  [ПЁТР, ОЛЬГА, ИГОРЬ].forEach(function (проигравший) {
    рейтинг.учестьПартию('дурак', партия(ЕКАТЕРИНА, проигравший));  // Екатерина: 3 победы = 30
  });
  [ПЁТР, ОЛЬГА].forEach(function (проигравший) {
    рейтинг.учестьПартию('дурак', партия(ИГОРЬ, проигравший));      // Игорь: 2 победы = 20
  });
  рейтинг.учестьПартию('дурак', партия(ОЛЬГА, ПЁТР));                // Ольга: 1 победа = 10
  // Пётр не выиграл ни разу — 0 очков, восьмое (последнее) место.
}

/** Ответ двери /рейтинг — собран РОВНО так же, как настоящая дверь
    в server/сервер.js (функция «таблицаРейтинга»): те же поля, тот же
    модуль server/рейтинг.js внутри, разница только в том, откуда взят
    номер игрока (см. «ктоИзПодписи» ниже). */
function ответДвери(игра, кто) {
  const срез = рейтинг.срезДляИгрока(игра, кто);
  return {
    ок: true,
    узналиВас: true,
    игра: срез.игра,
    всего: срез.всего,
    яВТаблице: срез.яВТаблице,
    я: срез.я,
    верхушка: срез.верхушка,
    вокругМеня: срез.вокругМеня,
    сила: срез.сила
  };
}

/* ---------------------------------------------------------------------
   2. Поддельная подпись Telegram — та же строка едет и в страницу,
      и внутрь неё, а наша копия двери разбирает эту же строку сама.
   --------------------------------------------------------------------- */

const ПОДПИСЬ = 'user=' + encodeURIComponent(JSON.stringify({ id: Я, first_name: 'Иван', last_name: 'Тестов' })) +
  '&auth_date=' + Math.floor(Date.now() / 1000) + '&hash=стенд-не-настоящая-подпись';

/** Номер игрока из подписи — БЕЗ проверки подлинности: это же не боевой
    сервер, подделывать тут больше нечего и незачем. Настоящий сервер
    так делать не должен (и не делает — см. server/сервер.js), а стенду
    для наполненного вида этого достаточно. */
function ктоИзПодписи(initData) {
  try {
    const поля = new URLSearchParams(String(initData || ''));
    const сырое = поля.get('user');
    if (!сырое) return null;
    const данные = JSON.parse(сырое);
    return Number.isInteger(данные.id) && данные.id > 0 ? данные.id : null;
  } catch (сбой) {
    return null;
  }
}

/* ---------------------------------------------------------------------
   3. Сервер страниц — раздача файлов + подмена Telegram
      (те же правила безопасности, что у tests/локальный-сервер.js
      и tests/поддельный-телеграм.js: слушаем только свой компьютер,
      папку bot и файлы с точкой не отдаём никогда).
   --------------------------------------------------------------------- */

const ТИПЫ = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8'
};

function безопасныйПуть(адрес) {
  return path.normalize(адрес).replace(/^(\.\.[\\/])+/, '').replace(/^[\\/]+/, '');
}

function причинаОтказа(адресДоРазбора, относительныйПуть) {
  const где = (адресДоРазбора + ' ' + относительныйПуть).toLowerCase();
  if (где.indexOf('.env') !== -1) return 'в этом файле лежит токен бота, наружу он не отдаётся';
  const части = относительныйПуть.split(/[\\/]/).filter(Boolean);
  if (части.length && части[0].toLowerCase() === 'bot') return 'папка bot закрыта: в ней настройки бота';
  for (const часть of части) {
    if (часть.charAt(0) === '.') return 'служебные файлы и папки, начинающиеся с точки, наружу не отдаются';
  }
  return null;
}

function внутриПроекта(файл) {
  const полный = path.resolve(файл);
  return полный === КОРЕНЬ || полный.startsWith(КОРЕНЬ + path.sep);
}

function отказать(ответ, код, текст) {
  ответ.writeHead(код, { 'Content-Type': 'text/plain; charset=utf-8' });
  ответ.end(текст);
}

/** Вырезать настоящий скрипт Telegram и вписать подделку с готовой подписью. */
function подменитьTelegram(html) {
  const скрипт = '<script>\n' + текстПодделки({ версия: '8.0', полныйЭкран: 'дают', подпись: ПОДПИСЬ }) + '</script>\n';
  const безНастоящего = html.replace(/<script[^>]*telegram-web-app\.js[^>]*>\s*<\/script>/gi,
    '<!-- настоящий скрипт Telegram вырезан стендом tests/рейтинг-наполненный.js -->');
  if (безНастоящего.indexOf('</head>') === -1) return скрипт + безНастоящего;
  return безНастоящего.replace('</head>', скрипт + '</head>');
}

const серверСтраниц = http.createServer(function (запрос, ответ) {
  const сырой = запрос.url.split('?')[0];
  let адрес;
  try { адрес = decodeURIComponent(сырой); } catch (ошибка) { отказать(ответ, 400, 'непонятный адрес'); return; }
  if (адрес === '/') адрес = '/index.html';

  const относительный = безопасныйПуть(адрес);
  const отказ = причинаОтказа(сырой + ' ' + адрес, относительный);
  if (отказ) { отказать(ответ, 403, 'доступ закрыт: ' + отказ); return; }

  const файл = path.join(КОРЕНЬ, относительный);
  if (!внутриПроекта(файл)) { отказать(ответ, 403, 'доступ закрыт: файл вне папки проекта'); return; }

  fs.readFile(файл, function (ошибка, данные) {
    if (ошибка) { отказать(ответ, 404, 'не найдено: ' + адрес); return; }
    const расширение = path.extname(файл).toLowerCase();
    ответ.writeHead(200, {
      'Content-Type': ТИПЫ[расширение] || 'application/octet-stream',
      'Cache-Control': 'no-store'
    });
    ответ.end(расширение === '.html' ? подменитьTelegram(данные.toString('utf8')) : данные);
  });
});

/* ---------------------------------------------------------------------
   4. Сервер комнат — только одна дверь, POST /рейтинг, с заголовками
      CORS: страница и эта дверь стоят на разных портах, без заголовков
      браузер такой запрос молча заблокирует.
   --------------------------------------------------------------------- */

function прочитатьТело(запрос) {
  return new Promise(function (готово) {
    let текст = '';
    запрос.on('data', function (ч) { текст += ч; if (текст.length > 1e6) запрос.destroy(); });
    запрос.on('end', function () { try { готово(JSON.parse(текст || '{}')); } catch (е) { готово({}); } });
  });
}

function заголовкиCORS(источник) {
  return {
    'Access-Control-Allow-Origin': источник || '*',
    'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
    'Access-Control-Allow-Headers': 'Content-Type, bypass-tunnel-reminder',
    'Access-Control-Max-Age': '86400',
    'Vary': 'Origin'
  };
}

const серверКомнат = http.createServer(async function (запрос, ответ) {
  const cors = заголовкиCORS(запрос.headers.origin);
  if (запрос.method === 'OPTIONS') { ответ.writeHead(204, cors); ответ.end(); return; }

  let адрес;
  try { адрес = decodeURIComponent(запрос.url.split('?')[0]); } catch (сбой) { адрес = запрос.url.split('?')[0]; }
  if (адрес !== '/рейтинг') {
    ответ.writeHead(404, Object.assign({ 'Content-Type': 'application/json; charset=utf-8' }, cors));
    ответ.end(JSON.stringify({ ошибка: 'в этой тестовой копии сервера комнат есть только дверь /рейтинг' }));
    return;
  }
  if (запрос.method !== 'POST') {
    ответ.writeHead(405, Object.assign({ 'Content-Type': 'application/json; charset=utf-8' }, cors));
    ответ.end(JSON.stringify({ ошибка: 'дверь /рейтинг слушает только POST' }));
    return;
  }

  const тело = await прочитатьТело(запрос);
  const игра = тело && typeof тело.игра === 'string' && тело.игра ? тело.игра : 'дурак';
  const кто = ктоИзПодписи(тело && тело.initData);
  console.log('  /рейтинг ← игра=' + игра + ', ' + (кто ? 'узнан игрок ' + кто : 'подписи нет — отвечаем «не узнали»'));

  const тИЗ = Object.assign({ 'Content-Type': 'application/json; charset=utf-8', 'Cache-Control': 'no-store' }, cors);
  if (!кто) {
    ответ.writeHead(200, тИЗ);
    ответ.end(JSON.stringify({
      ок: false, узналиВас: false, игра: игра,
      причина: 'Рейтинг ведётся только для игры в Telegram: иначе игрока не отличить от другого'
    }));
    return;
  }
  ответ.writeHead(200, тИЗ);
  ответ.end(JSON.stringify(ответДвери(игра, кто)));
});

