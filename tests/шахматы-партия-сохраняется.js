function клетка(э, поле) {
  return э.document.getElementById('доска').children.find(function (к) { return к.getAttribute('data-поле') === поле; }) || null;
}

function тап(э, поле) {
  const к = клетка(э, поле);
  if (к) э.document.getElementById('доска')._emit('click', { target: к });
  return Boolean(к);
}

/** Какая фигура стоит в клетке: «белая пешка», '' для пустой, null — клетки нет. */
function фигураВКлетке(э, поле) {
  const к = клетка(э, поле);
  if (!к) return null;
  const знак = найтиПоКлассу(к, 'фигура');
  if (!знак) return '';
  const классы = знак.className.split(' ');
  const цвет = классы.indexOf('фигура--белая') !== -1 ? 'белая' : классы.indexOf('фигура--чёрная') !== -1 ? 'чёрная' : '';
  const тип = классы.filter(function (c) { return c.indexOf('фигура--') === 0 && c !== 'фигура--белая' && c !== 'фигура--чёрная'; })[0];
  return тип ? цвет + ' ' + тип.slice('фигура--'.length) : '';
}

function ждать(мс) { return new Promise(function (готово) { setTimeout(готово, мс); }); }

/** Ход человека: два тапа, потом ждём ответ бота (если он есть). */
async function ход(э, откуда, куда) {
  тап(э, откуда);
  тап(э, куда);
  await ждать(30);
}

