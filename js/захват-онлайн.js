/* =====================================================================
   «ЗАХВАТ»: ИГРА ПО СЕТИ (этап В9, ТЗ 3.1, 7.1, 8.3, 15.3; этап В9а).

   Что делает файл:
   - подключает игру к общему онлайн-лобби (js/онлайн-лобби.js): места
     2–6, обычно 4; хозяин выбирает «Раундов: 10 · 15 · 20» — выбор уходит
     в настройки стола полем раундовЗахвата (числом, сервер сверяет строго);
   - ставит мост ИграПоСети: js/сеть.js отдаёт сюда вид сервера, а мы
     рисуем по нему стол;
   - стол на странице ОДИН (В9а): его создаёт js/захват-экран.js и отдаёт
     дверью ЗахватЭкран.столДляСети. Своего стола здесь нет: каждый
     ЗахватСтол.создать вешает обработчики на те же кнопки, и второй стол
     испортил бы сохранённую партию с ботами;
   - шлёт черновик через Сеть.отправитьЧерновик не на каждую правку, а
     через 400 мс тишины: последняя правка побеждает; правка прошлого
     раунда (или прошлой партии — реванш) выбрасывается при новом раунде;
   - «Готово» и «Изменить» — один признак «ход в пути»: пока ход летит,
     кнопка заперта и второй ход не уходит;
   - отказ сервера показывается, только если раунд на экране тот же, что
     у запроса; отказ «Раунд уже разыгран» — пилюлей «Раунд уже разыгран —
     отдавайте приказы на новый» (ТЗ 3.1, решение штаба 01.10 20:32).

   Вид здесь не задаётся: из кода — только классы, атрибуты и текст.
   Рисунков код не делает: холст карты раскладывает только готовые
   рисунки через js/захват-карта-вид.js (пачки Кодекса пока нет).
   Подключать после js/захват-экран.js и js/онлайн-лобби.js, до js/сеть.js.
   ===================================================================== */
(function () {
  if (typeof document === 'undefined') return;   // под node страницы нет

  const Правила = window.ЗахватПравила;
  const Экран = window.ЗахватЭкран;
  if (!Экран || typeof Экран.столДляСети !== 'function') {
    // Без экрана стола нет вовсе: модуль подключён раньше js/захват-экран.js.
    console.warn('Захват по сети: нет js/захват-экран.js — игра по сети не подключена');
    return;
  }
  const $ = id => document.getElementById(id);

  const ИГРА = 'захват';
  // Слово в слово как отказ сервера (server/игры/захват.js, устаревшийХод).
  const ОТКАЗ_СТАРОГО_РАУНДА = 'Раунд уже разыгран';
  const ПИЛЮЛЯ_СТАРОГО_РАУНДА = 'Раунд уже разыгран — отдавайте приказы на новый';
  // Группа пилюль «Раундов» на экране стола по сети. В разметке её пока нет —
  // узел ставит штаб; без него выбор живёт только в двери выбратьРаунды().
  const ГРУППА_РАУНДОВ = 'захват-онлайн-раунды';
  // Ширина карты, пока узел ещё не измерен: ширина колонки игры (как у экрана с ботами).
  const ШИРИНА_КАРТЫ_ЗАПАС = 358;
  // Рисунки Кодекса для карты ещё не приняты (этап Г1): холст пустой, заглушек нет.
  const РИСУНКИ_КАРТЫ = {};

  let выбраноРаундов = Правила.ЧИСЛА.раундов.обычно;
  let стол = null;               // общий стол страницы, берётся у экрана при первом виде партии
  let слушаемОстаток = false;    // свой слушатель «Готово» (лист остатка) повешен
  let сетевой = null;            // последний принятый вид сервера
  let ключРаунда = null;         // стол · партия · раунд, который сейчас на экране
  let ждущий = null;             // { раунд, черновик } — правка, ждущая своих 400 мс
  let таймерЧерновика = null;
  let ходВПути = null;           // номер летящего «Готово» или «Изменить»; null — ничего не летит
  let номерХода = 0;
  let пилюляЖдёт = false;        // сервер сказал «Раунд уже разыгран», а свежий вид ещё не пришёл
  let молчим = false;            // стол выравнивается по виду — это не правка человека
  let поСети = false;
  let видКарты = null;           // зум и сдвиг карты от стола

  /* ---------- выбор хозяина «Раундов» и стол для лобби ---------- */

  /** Выбрать число раундов. Не из вариантов правил — не принимаем и оставляем прежнее. */
  function выбратьРаунды(значение) {
    const число = Number(значение);
    if (Правила.ЧИСЛА.раундов.варианты.indexOf(число) === -1) return false;
    выбраноРаундов = число;
    отметитьРаунды();
    return true;
  }

  function отметитьРаунды() {
    const группа = $(ГРУППА_РАУНДОВ);
    if (!группа) return;
    группа.querySelectorAll('button').forEach(кнопка => {
      кнопка.setAttribute('aria-checked', кнопка.getAttribute('data-значение') === String(выбраноРаундов) ? 'true' : 'false');
    });
  }

  function слушатьГруппуРаундов() {
    const группа = $(ГРУППА_РАУНДОВ);
    if (!группа) return;
    группа.addEventListener('click', событие => {
      const кнопка = событие.target && событие.target.closest ? событие.target.closest('button') : null;
      if (кнопка && группа.contains(кнопка)) выбратьРаунды(кнопка.getAttribute('data-значение'));
    });
    отметитьРаунды();
  }

  /** Настройки стола для ОнлайнЛобби: только данные, пределы проверяет сервер. */
  function настройкиСтола() {
    return { раундовЗахвата: выбраноРаундов };
  }

  function создатьСтол() {
    if (!window.ОнлайнЛобби) return Promise.resolve({ ок: false, причина: 'Онлайн-лобби не загрузилось — обновите страницу.' });
    return window.ОнлайнЛобби.создатьСтол(ИГРА);
  }

  /* ---------- вид сервера → партия для стола ----------
     Стол и правила работают с партией по ключам мест. Ключами здесь служат
     номера мест из вида (в хозяевах вида тоже номера), а порядок игроков —
     по полю «цвет»: по нему карта-вид выбирает цвет хозяина. */

  function партияИзВида(з) {
    const игроки = з.игроки.slice().sort((а, б) => а.цвет - б.цвет);
    const подкрепление = {}, выбыли = {}, сдались = {}, ушлоВРаунде = {};
    игроки.forEach(и => {
      подкрепление[и.номер] = и.подкрепление;
      if (и.выбыл) выбыли[и.номер] = true;
      if (и.сдался) сдались[и.номер] = true;
      if (и.ушёл) ушлоВРаунде[и.номер] = з.раунд;
    });
    if (з.моёПодкрепление) подкрепление[з.я] = з.моёПодкрепление.всего;
    return {
      карта: з.карта,
      раунд: з.раунд,
      всегоРаундов: з.всегоРаундов,
      игроки: игроки.map(и => и.номер),
      хозяева: з.хозяева.slice(),
      войска: з.войска.slice(),
      столицы: з.столицы.map(с => ({ область: с.область, хозяинНаСтарте: с.хозяинНаСтарте })),
      подкрепление: подкрепление,
      выбыли: выбыли,
      сдались: сдались,
      ушлоВРаунде: ушлоВРаунде
    };
  }

  function инфоИзВида(з) {
    const инфо = { имена: {}, готовы: {}, боты: {}, спят: {} };
    з.игроки.forEach(и => {
      инфо.имена[и.номер] = и.имя;
      if (и.готов) инфо.готовы[и.номер] = true;
      if (и.этоБот) инфо.боты[и.номер] = true;
      if (и.спит) инфо.спят[и.номер] = true;
    });
    return инфо;
  }

  /** Свой черновик с сервера — после перезагрузки или возврата за стол он не теряется. */
  function черновикИзВида(з) {
    const ч = з.мойЧерновик || {};
    return {
      расстановка: Object.assign({}, ч.расстановка || {}),
      приказы: (ч.приказы || []).map(п => ({ из: п.из, в: п.в, сколько: п.сколько }))
    };
  }

  const раундСейчас = () => (сетевой && сетевой.захват ? сетевой.захват.раунд : null);

  /* ---------- экраны и холст ---------- */

  /** Экран — через дверь экрана: она же освежает стрелку Telegram, лист «⋯» и лобби. */
  function экран(id) {
    Экран.показатьЭкран(id);
    if (id !== 'экран-игры') закрытьЛистОстатка();
  }

  function ширинаКарты() {
    const узел = $('захват-карта');
    return узел && узел.clientWidth > 0 ? узел.clientWidth : ШИРИНА_КАРТЫ_ЗАПАС;
  }

  /** Холст карты: только готовые рисунки через карту-вид, как у партии с ботами. */
  function нарисоватьКарту() {
    if (!сетевой || !сетевой.захват || !window.ЗахватКартаВид) return;
    const холст = $('захват-холст');
    const ctx = холст && typeof холст.getContext === 'function' ? холст.getContext('2d') : null;
    if (!ctx) return;
    const ширина = ширинаКарты();
    const раскладка = window.ЗахватКартаВид.собратьРаскладку(партияИзВида(сетевой.захват), { ширина: ширина });
    const плотность = window.devicePixelRatio || 1;
    const ширинаХолста = Math.round(ширина * плотность);
    const высотаХолста = Math.round(раскладка.геометрия.высота * плотность);
    if (холст.width !== ширинаХолста) холст.width = ширинаХолста;
    if (холст.height !== высотаХолста) холст.height = высотаХолста;
    const вид = видКарты || { зум: 1, сдвигX: 0, сдвигY: 0 };
    window.ЗахватКартаВид.нарисовать(ctx, раскладка, РИСУНКИ_КАРТЫ, {
      ширинаХолста: ширинаХолста, высотаХолста: высотаХолста,
      зум: вид.зум * плотность, сдвигX: вид.сдвигX * плотность, сдвигY: вид.сдвигY * плотность
    });
  }

  /* ---------- отказы сервера ---------- */

  /**
   * Отказ сервера на запрос, отправленный в раунде ключЗапроса.
   * «Раунд уже разыгран» — пилюля (ТЗ 3.1). Любой другой — словами в подсказку,
   * но только если на экране всё тот же раунд: ответ про ушедший раунд
   * новому раунду не нужен и запутал бы человека.
   */
  function сказатьОтказ(ответ, ключЗапроса) {
    if (!ответ || ответ.принято || !ответ.причина) return;
    if (ответ.причина === ОТКАЗ_СТАРОГО_РАУНДА) { пилюляСтарогоРаунда(ключЗапроса); return; }
    if (ключЗапроса !== ключРаунда) return;
    const подсказка = $('захват-подсказка');
    if (!подсказка) return;
    подсказка.textContent = ответ.причина;
    подсказка.classList.add('захват-подсказка--отказ');
  }

  /** Пилюля — уже на новом раунде: если свежий вид ещё в пути, она ждёт его. */
  function пилюляСтарогоРаунда(ключЗапроса) {
    // Ушли из стола сети, стол у партии с ботами: пилюля про сетевой раунд ей не нужна.
    if (!поСети || Экран.режимСтола() !== 'сеть') return;
    if (ключЗапроса === ключРаунда) { пилюляЖдёт = true; return; }
    Экран.показатьПилюлю(ПИЛЮЛЯ_СТАРОГО_РАУНДА);
  }

  /* ---------- черновик: 400 мс тишины, последняя правка побеждает ---------- */

  function послатьЧерновик(раунд, черновик, ключЗапроса) {
    if (!window.Сеть || typeof window.Сеть.отправитьЧерновик !== 'function') return Promise.resolve(null);
    return window.Сеть.отправитьЧерновик(раунд, черновик).then(ответ => {
      сказатьОтказ(ответ, ключЗапроса);
      return ответ;
    });
  }

  /* Правка прошлого раунда сюда не доходит: новый раунд (и новая партия)
     забывает ждущую правку в показатьВид — забытьЖдущий(). */
  function отправитьЖдущий() {
    таймерЧерновика = null;
    const правка = ждущий;
    ждущий = null;
    if (!правка) return Promise.resolve(null);
    return послатьЧерновик(правка.раунд, правка.черновик, ключРаунда);
  }

  function черновикИзменён(черновик) {
    if (молчим || !поСети) return;
    ждущий = { раунд: раундСейчас(), черновик: черновик };
    clearTimeout(таймерЧерновика);
    таймерЧерновика = setTimeout(отправитьЖдущий, Правила.ЧИСЛА.задержкаЧерновикаМс);
  }

  function забытьЖдущий() {
    clearTimeout(таймерЧерновика);
    таймерЧерновика = null;
    ждущий = null;
  }

  /* ---------- «Готово» и «Изменить»: один ход в пути ---------- */

  function молча(дело) {
    молчим = true;
    try { дело(); } finally { молчим = false; }
  }

  /** Пока ход летит, кнопка «Готово/Изменить» заперта: стол открывает её при каждой перерисовке, запираем снова. */
  function замокКнопки() {
    const кнопка = $('захват-готово');
    if (ходВПути !== null && кнопка) кнопка.setAttribute('disabled', '');
  }

  function начатьПолёт() {
    номерХода++;
    ходВПути = номерХода;
    замокКнопки();
    return номерХода;
  }

  /** Ход долетел. Новый раунд мог уже снять этот полёт (или летит следующий) — тогда не трогаем. */
  function закончитьПолёт(полёт) {
    if (ходВПути !== полёт) return;
    ходВПути = null;
    // Стол сам решает, открыта ли кнопка (в игре ли я): перерисовываем его по последнему виду.
    if (стол && сетевой && сетевой.захват) стол.обновитьПартию(партияИзВида(сетевой.захват), инфоИзВида(сетевой.захват));
    сверитьГотовность();
  }

  /** «Готово» стола: сперва черновик целиком (сервер берёт приказы из него), потом ход. */
  function готовоНажато(черновик) {
    if (молчим || !поСети) return;
    // Ещё летит «Изменить»: «Готово» его не обгоняет — стол возвращаем как был, на сервер ничего не идёт.
    if (ходВПути !== null) { молча(() => { if (стол.готов()) стол.изменить(); }); замокКнопки(); return; }
    закрытьЛистОстатка();
    забытьЖдущий();
    const раунд = раундСейчас();
    const ключ = ключРаунда;
    const полёт = начатьПолёт();
    return послатьЧерновик(раунд, черновик, ключ).then(ответ => {
      if (!ответ || !ответ.принято) return null;
      return window.Сеть.отправитьХод({ действие: 'готово', раунд: раунд }).then(итог => {
        сказатьОтказ(итог, ключ);
        return итог;
      });
    }).then(итог => {
      // Не дошло — человек снова правит черновик; отказ уже сказан словами.
      // Только в том же раунде: ✓ нового раунда — уже другое «Готово».
      if ((!итог || !итог.принято) && ключ === ключРаунда) молча(() => { if (стол.готов()) стол.изменить(); });
      закончитьПолёт(полёт);
    });
  }

  function изменитьНажато() {
    if (молчим || !поСети) return;
    // «Изменить» не обгоняет летящее «Готово»: стол возвращаем к ✓, на сервер ничего не идёт.
    if (ходВПути !== null) { молча(() => { if (!стол.готов()) стол.нажатьГотово(); }); замокКнопки(); return; }
    const ключ = ключРаунда;
    const полёт = начатьПолёт();
    return window.Сеть.отправитьХод({ действие: 'изменить', раунд: раундСейчас() }).then(итог => {
      сказатьОтказ(итог, ключ);
      закончитьПолёт(полёт);
    });
  }

  /* Лист «Осталось N войск. Поставить…?» — свой, с другими id, чем у партии
     с ботами: её экран ищет свой лист по id и не должен найти этот. */
  function листОстатка() {
    let лист = $('захват-онлайн-остаток');
    if (лист) return лист;
    лист = document.createElement('div');
    лист.id = 'захват-онлайн-остаток';
    лист.className = 'захват-лист скрыт';
    лист.setAttribute('role', 'dialog');
    лист.setAttribute('aria-labelledby', 'захват-онлайн-остаток-вопрос');
    const вопрос = document.createElement('h2');
    вопрос.id = 'захват-онлайн-остаток-вопрос';
    const да = document.createElement('button');
    да.id = 'захват-онлайн-остаток-да';
    да.className = 'кнопка кнопка--главная';
    да.setAttribute('type', 'button');
    да.textContent = 'Поставить и готово';
    const нет = document.createElement('button');
    нет.id = 'захват-онлайн-остаток-нет';
    нет.className = 'кнопка';
    нет.setAttribute('type', 'button');
    нет.textContent = 'Вернуться';
    лист.append(вопрос, да, нет);
    $('экран-игры').appendChild(лист);
    да.addEventListener('click', () => { закрытьЛистОстатка(); стол.поставитьОстатокИГотово(); });
    нет.addEventListener('click', () => { закрытьЛистОстатка(); стол.отказатьсяОтВопроса(); });
    return лист;
  }

  function закрытьЛистОстатка() {
    const лист = $('захват-онлайн-остаток');
    if (лист) лист.classList.add('скрыт');
  }

  const поставлено = черновик => Object.keys(черновик.расстановка).reduce((сумма, к) => сумма + черновик.расстановка[к], 0);

  /** После «Готово»: стол спросил про остаток подкрепления — показываем вопрос листом. */
  function спроситьОбОстатке() {
    if (!поСети || Экран.режимСтола() !== 'сеть') return;   // стол слушает партию с ботами — у неё свой лист
    if (!стол || стол.готов() || !сетевой || !сетевой.захват) return;
    const з = сетевой.захват;
    const партия = партияИзВида(з);
    if (!Правила.вИгре(партия, з.я)) return;
    const черновик = стол.черновик();
    if (!Правила.проверитьЧерновик(партия, з.я, черновик).принято) return;
    if ((партия.подкрепление[з.я] || 0) - поставлено(черновик) <= 0) return;
    const лист = листОстатка();
    $('захват-онлайн-остаток-вопрос').textContent = $('захват-подсказка').textContent;
    лист.classList.remove('скрыт');
  }

  /* ---------- выход из стола: «‹», «В меню», «Сдаться» ---------- */

  /** «Да, сдаться» за сетевым столом: сдача уходит серверу, партия с ботами её не видит. */
  function сдаться() {
    if (!поСети || !window.Сеть || typeof window.Сеть.отправитьХод !== 'function') return Promise.resolve(null);
    const ключ = ключРаунда;
    return window.Сеть.отправитьХод({ действие: 'сдаться' }).then(ответ => {
      сказатьОтказ(ответ, ключ);
      return ответ;
    });
  }

  /* Слова подтверждения ухода (ТЗ 3.8–3.9): вдвоём уход кончает партию,
     втроём и больше место водит бот. Строка листа и кнопки — как у домино. */
  const СЛОВА_УХОДА = { строка: 'Выйти из партии', заголовок: 'Выйти из партии?', да: 'Выйти', нет: 'Остаться' };
  const УХОД_ВДВОЁМ = 'Партия закончится.';
  const УХОД_С_БОТОМ = 'Ваше место займёт бот.';

  /**
   * Слова для окна «Выйти из партии?» или null — спрашивать не о чем и «‹»
   * выходит сразу: партия по виду сервера не идёт (конец) или я уже вне игры
   * (выбыл, сдался) — тогда уход ничего не меняет и обещать «место займёт бот» нечестно.
   */
  function словаВыхода() {
    if (!поСети || !сетевой || !сетевой.захват) return null;
    if (сетевой.этап !== 'игра' || сетевой.завершена === true) return null;
    const з = сетевой.захват;
    if (!Правила.вИгре(партияИзВида(з), з.я)) return null;
    return Object.assign({ текст: з.игроки.length === 2 ? УХОД_ВДВОЁМ : УХОД_С_БОТОМ }, СЛОВА_УХОДА);
  }

  /** «‹» и «В меню» за сетевым столом (после подтверждения): выйти из стола сети и вернуться в лобби. */
  function выйтиИзСтола() {
    if (window.Сеть && typeof window.Сеть.покинутьПартию === 'function') window.Сеть.покинутьПартию();
    вМеню();
  }

  function вМеню() {
    сбросить();
    поСети = false;
    Экран.отпуститьСтол();
    экран('экран-лобби');
  }

  /* ---------- стол из вида ---------- */

  // Слушатели общего стола и двери выхода — экран зовёт их, пока стол в режиме «сеть».
  const ДВЕРИ_СЕТИ = {
    приИзменении: черновикИзменён,
    приГотово: готовоНажато,
    приИзменить: изменитьНажато,
    приВиде: вид => { видКарты = вид; нарисоватьКарту(); },
    выйти: выйтиИзСтола,
    словаВыхода: словаВыхода,
    сдаться: сдаться
  };

  /** Общий стол страницы в режиме «сеть»: партию с ботами экран при этом откладывает. */
  function достатьСтол() {
    стол = Экран.столДляСети(ДВЕРИ_СЕТИ);
    if (!слушаемОстаток) {
      слушаемОстаток = true;
      // Стол слушает «Готово» сам; этот слушатель идёт после него и видит, что стол спросил про остаток.
      $('захват-готово').addEventListener('click', спроситьОбОстатке);
    }
    return стол;
  }

  /** Поставить раунд из вида: черновик — с сервера, ✓ — как у сервера. */
  function поставитьРаунд(з) {
    const с = достатьСтол();
    молча(() => {
      с.задатьРаскрытие(false);
      с.начатьРаунд(партияИзВида(з), з.я, инфоИзВида(з), черновикИзВида(з));
      if (з.яГотов) {
        const ответ = с.нажатьГотово();
        // Сервер ставит остаток по тому же правилу 3.3 — повторяем, чтобы ✓ сошлась.
        if (ответ && ответ.вопрос) с.поставитьОстатокИГотово();
      }
    });
    с.показатьСлой(ширинаКарты());
  }

  /** ✓ на экране и на сервере разошлись (другое устройство, отказ) — верим серверу. */
  function сверитьГотовность() {
    if (ходВПути !== null || !стол || !сетевой || !сетевой.захват) return;
    if (!!сетевой.захват.яГотов !== стол.готов()) поставитьРаунд(сетевой.захват);
  }

  function показатьВид(вид) {
    if (!вид || !вид.захват) return;
    // Опоздавший вид того же стола не перерисовывает свежий.
    if (сетевой && сетевой.код === вид.код && Number(вид.версия) < Number(сетевой.версия)) return;
    поСети = true;
    сетевой = вид;
    const з = вид.захват;
    // Режим — ДО того, как сеть возьмёт стол: если между видами стол успел уйти к партии
    // с ботами («Ещё партия», «Продолжить»), на нём её черновик, её «я» и подсказка новичка —
    // подправить такой стол нельзя, его ставим заново, как новый раунд.
    const столБылУБотов = Экран.режимСтола() !== 'сеть';
    достатьСтол();
    экран('экран-игры');
    const ключ = [вид.код, вид.сыграноПартий, з.раунд].join('|');
    if (ключ !== ключРаунда || столБылУБотов) {
      ключРаунда = ключ;
      забытьЖдущий();   // правка прошлого раунда (или прошлой партии — реванш, тот же номер раунда) не уходит
      // Летящий ход прошлого раунда новый раунд не держит: его ответ сверит раунд сам.
      ходВПути = null;
      закрытьЛистОстатка();
      поставитьРаунд(з);
      Экран.показатьПилюлю(пилюляЖдёт ? ПИЛЮЛЯ_СТАРОГО_РАУНДА : '');
      пилюляЖдёт = false;
    } else {
      // Тот же раунд: другие нажали ✓ или ушли — свой черновик не трогаем.
      стол.обновитьПартию(партияИзВида(з), инфоИзВида(з));
      замокКнопки();
      сверитьГотовность();
    }
    нарисоватьКарту();
  }

  function сбросить() {
    забытьЖдущий();
    if (Экран.режимСтола() === 'сеть') Экран.показатьПилюлю('');
    сетевой = null;
    ключРаунда = null;
    ходВПути = null;
    пилюляЖдёт = false;
    закрытьЛистОстатка();
  }

  /* ---------- подключение ---------- */

  if (window.ОнлайнЛобби && typeof window.ОнлайнЛобби.подключить === 'function') {
    const места = Правила.ЧИСЛА.мест;
    window.ОнлайнЛобби.подключить({
      игра: ИГРА,
      мест: { мин: места.мин, макс: места.макс, обычно: места.поУмолчанию },
      настройкиСтола: настройкиСтола
    });
  }

  // Видимая «Создать игру» на #экран-друга: стол создаёт онлайн-лобби (компания,
  // открытый, раунды хозяина). Слушаем в фазе захвата и гасим штатный обработчик
  // js/сеть.js — иначе ушёл бы стол без раундов, как у домино до перехода.
  const кнопкаСоздать = $('кнопка-создать-игру');
  if (кнопкаСоздать) {
    кнопкаСоздать.addEventListener('click', событие => {
      событие.stopImmediatePropagation();
      событие.preventDefault();
      if (кнопкаСоздать.disabled) return;
      кнопкаСоздать.disabled = true;
      создатьСтол().then(() => { кнопкаСоздать.disabled = false; });
    }, true);
  }

  слушатьГруппуРаундов();

  window.ИграПоСети = {
    начать() { поСети = true; сбросить(); },
    показатьВид: показатьВид,
    показатьСвязь(текст) {
      const строка = $('строка-связи');
      if (!строка) return;
      строка.textContent = текст || '';
      строка.classList.toggle('скрыт', !текст);
    },
    экран: экран,
    вМеню: вМеню,
    идёт: () => поСети
  };

  /* Двери наружу — для проверки tests/захват-онлайн.js и следующих этапов. */
  window.ЗахватОнлайн = {
    выбратьРаунды: выбратьРаунды,
    выбраноРаундов: () => выбраноРаундов,
    настройкиСтола: настройкиСтола,
    создатьСтол: создатьСтол,
    стол: () => стол,
    партияИзВида: партияИзВида
  };
})();
