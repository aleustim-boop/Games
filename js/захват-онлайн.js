  function партияИзВида(з) {
    const игроки = з.игроки.slice().sort((а, б) => а.цвет - б.цвет);
    const подкрепление = {}, выбыли = {}, сдались = {}, ушлоВРаунде = {};
    игроки.forEach(и => {
      подкрепление[и.номер] = и.подкрепление;
      if (и.выбыл) выбыли[и.номер] = true;
      if (и.сдался) сдались[и.номер] = true;
      if (и.ушёл) ушлоВРаунде[и.номер] = з.раунд;
    });
    if (з.моёПодкрепление) подкрепление[з.я] = з.моёПодкрепление.всего;
    return {
      карта: з.карта,
      раунд: з.раунд,
      всегоРаундов: з.всегоРаундов,
      игроки: игроки.map(и => и.номер),
      хозяева: з.хозяева.slice(),
      войска: з.войска.slice(),
      столицы: з.столицы.map(с => ({ область: с.область, хозяинНаСтарте: с.хозяинНаСтарте })),
      подкрепление: подкрепление,
      выбыли: выбыли,
      сдались: сдались,
      ушлоВРаунде: ушлоВРаунде
    };
  }

  /**
   * Партия, которую видно на карте и в слое шайб стола. Пока раскрытие не дошло до итоговой карты —
   * хозяева «до» (налив перекрасит области по ходу боёв) и войска «до», если они известны: иначе шайбы
   * заранее выдали бы, чем кончились бои. Как у партии с ботами (экран отдаёт столу партию «до»).
   */
  function партияНаКарте(з) {
    const партия = партияИзВида(з);
    if (!раскрытие || раскрытие.итоговаяКарта) {
      // Партия кончилась: номер раунда после последнего разбора не растёт, и стол по нему не отличил бы
      // свой старый черновик от свежего — «завершена» говорит ему не считать расстановку второй раз.
      партия.завершена = партияЗакончена();
      return партия;
    }
    партия.хозяева = раскрытие.хозяеваДо.slice();
    if (раскрытие.войскаДо) партия.войска = раскрытие.войскаДо.slice();
    return партия;
  }

  function инфоИзВида(з) {
    const инфо = { имена: {}, готовы: {}, боты: {}, спят: {} };
    з.игроки.forEach(и => {
      инфо.имена[и.номер] = и.имя;
      if (и.готов) инфо.готовы[и.номер] = true;
      if (и.этоБот) инфо.боты[и.номер] = true;
      if (и.спит) инфо.спят[и.номер] = true;
    });
    return инфо;
  }

  /** Свой черновик с сервера — после перезагрузки или возврата за стол он не теряется. */
  function черновикИзВида(з) {
    const ч = з.мойЧерновик || {};
    return {
      расстановка: Object.assign({}, ч.расстановка || {}),
      приказы: (ч.приказы || []).map(п => ({ из: п.из, в: п.в, сколько: п.сколько }))
    };
  }

  const раундСейчас = () => (сетевой && сетевой.захват ? сетевой.захват.раунд : null);

  /** Партия кончилась по виду сервера: правок и ходов больше нет, пока не начнётся новая партия. */
  const партияЗакончена = () => !!(сетевой && сетевой.завершена === true);

  /* ---------- экраны и холст ---------- */

  /** Экран — через дверь экрана: она же освежает стрелку Telegram, лист «⋯» и лобби. */
  function экран(id) {
    Экран.показатьЭкран(id);
    if (id !== 'экран-игры') { закрытьЛистОстатка(); закрытьПоставитьСюда(); }
  }

  function ширинаКарты() {
    const узел = $('захват-карта');
    return узел && узел.clientWidth > 0 ? узел.clientWidth : ШИРИНА_КАРТЫ_ЗАПАС;
  }

  /* Рисунки карты — так же, как у партии с ботами (js/захват-экран.js): набор — листы цветов стола
     и своего режима, грузится один раз на набор. Пока картинки идут, карта рисуется без них;
     битый рисунок карта-вид сам пишет в консоль, замен нет. */
  let картинкиКарты = {};          // готовые картинки набора: имя -> картинка
  let ключНабораРисунков = null;   // набор, который уже грузится или готов
  let рисункиГотовы = false;       // набор догружен: шайбам, пилюлям и значкам стола можно показаться
  let лёгкийНабор = false;         // режим набора: раскладка собирается в том же режиме, что и картинки
  let номерЗагрузки = 0;           // ответ устаревшей загрузки не должен лечь поверх нового набора
  let протяжкаПальцем = null;      // { откуда, x, y }: стрелка за пальцем, пока игрок тянет приказ

  /** «Эффекты стекла» (ТЗ 10): в памяти ключ «эффекты», значение 'лёгкие' — лёгкий набор; всё прочее — полный. */
  const лёгкийРежим = () => !!Память && Память.взять('эффекты', 'полные') === 'лёгкие';

  /** Стол общий: говорим ему про рисунки, только пока он у сети (иначе его хозяин — партия с ботами). */
  function сказатьСтолуРисунки(есть) {
    if (стол && Экран.режимСтола() === 'сеть') стол.задатьРисунки(есть);
  }

  function подготовитьРисунки(партия) {
    const КартаВид = window.ЗахватКартаВид;
    if (!КартаВид) return;
    const лёгкий = лёгкийРежим();
    let список;
    try {
      список = КартаВид.нужныеРисунки(партия, лёгкий);
    } catch (ошибка) {
      console.error('Захват по сети: не вышло понять, какие рисунки нужны карте', ошибка);
      return;
    }
    const ключ = (лёгкий ? 'лёгкий|' : 'полный|') + список.map(р => р.имя).join(',');
    if (ключ === ключНабораРисунков) { сказатьСтолуРисунки(рисункиГотовы); return; }
    ключНабораРисунков = ключ;
    картинкиКарты = {};
    рисункиГотовы = false;
    лёгкийНабор = лёгкий;
    сказатьСтолуРисунки(false);
    const номер = ++номерЗагрузки;
    КартаВид.загрузитьРисунки(список).then(итог => {
      if (номер !== номерЗагрузки) return;
      // Что-то не догрузилось: набор не считаем готовым, следующий раунд попробует снова (ошибку пишет карта-вид).
      if (итог.нет && итог.нет.length) ключНабораРисунков = null;
      картинкиКарты = итог.картинки;
      рисункиГотовы = Object.keys(итог.картинки).length > 0;
      сказатьСтолуРисунки(рисункиГотовы);
      нарисоватьКарту();
    });
  }

  let кадрЖдёт = false;

  /** Перерисовка на движение пальца: не чаще раза за кадр, последнее положение дорисовывается; без requestAnimationFrame — сразу. */
  function нарисоватьКартуПоКадру() {
    if (typeof window.requestAnimationFrame !== 'function') { нарисоватьКарту(); return; }
    if (кадрЖдёт) return;
    кадрЖдёт = true;
    window.requestAnimationFrame(() => { кадрЖдёт = false; нарисоватьКарту(); });
  }

  /**
   * Холст карты: только готовые рисунки через карту-вид, как у партии с ботами. Холст — на весь узел
   * карты (море на всей площади), карта по центру — по ЗахватСтол.местоКарты, как и слой шайб стола.
   */
  function нарисоватьКарту() {
    if (!столУСети() || !сетевой || !сетевой.захват || !window.ЗахватКартаВид) return;
    const холст = $('захват-холст');
    const ctx = холст && typeof холст.getContext === 'function' ? холст.getContext('2d') : null;
    if (!ctx) return;
    const партия = партияНаКарте(сетевой.захват);
    const узелКарты = $('захват-карта');
    const ширинаУзла = ширинаКарты();
    const высотаУзла = узелКарты && узелКарты.clientHeight > 0 ? узелКарты.clientHeight : 0;
    const место = window.ЗахватСтол.местоКарты(партия, ширинаУзла, высотаУзла);
    // Эффекты раскрытия (стрелки, вспышки, налив) — только пока идёт раскрытие; потом список пуст.
    // «Своё» (выбор, цели, цель новичка, стрелки приказов) отдаёт стол одним вызовом — как у партии с ботами.
    const своё = стол ? стол.параметрыХолста() : {};
    const параметрыРаскладки = Object.assign({ ширина: место.ширина, лёгкий: лёгкийНабор }, своё,
      раскрытие ? эффектыРаскрытия.параметры() : {});
    if (протяжкаПальцем) параметрыРаскладки.протяжка = Object.assign({ кто: сетевой.захват.я }, протяжкаПальцем);
    const раскладка = window.ЗахватКартаВид.собратьРаскладку(партия, параметрыРаскладки);
    const плотность = window.devicePixelRatio || 1;
    const ширинаХолста = Math.round(ширинаУзла * плотность);
    const высотаХолста = Math.round((высотаУзла || раскладка.геометрия.высота) * плотность);
    if (холст.width !== ширинаХолста) холст.width = ширинаХолста;
    if (холст.height !== высотаХолста) холст.height = высотаХолста;
    const вид = видКарты || { зум: 1, сдвигX: 0, сдвигY: 0 };
    window.ЗахватКартаВид.нарисовать(ctx, раскладка, картинкиКарты, {
      ширинаХолста: ширинаХолста, высотаХолста: высотаХолста, плотность: плотность,
      зум: вид.зум * плотность,
      сдвигX: (место.x + вид.сдвигX) * плотность, сдвигY: (место.y + вид.сдвигY) * плотность
    });
  }

  /* ---------- отказы сервера ---------- */

  /**
   * Отказ сервера на запрос, отправленный в раунде ключЗапроса.
   * «Раунд уже разыгран» — пилюля (ТЗ 3.1). Любой другой — словами в подсказку,
   * но только если на экране всё тот же раунд: ответ про ушедший раунд
   * новому раунду не нужен и запутал бы человека.
   */
  function сказатьОтказ(ответ, ключЗапроса) {
    if (!ответ || ответ.принято || !ответ.причина) return;
    if (ответ.причина === ОТКАЗ_СТАРОГО_РАУНДА) { пилюляСтарогоРаунда(ключЗапроса); return; }
    if (ключЗапроса !== ключРаунда) return;
    const подсказка = $('захват-подсказка');
    if (!подсказка) return;
    подсказка.textContent = ответ.причина;
    подсказка.classList.add('захват-подсказка--отказ');
  }

  /** Пилюля — уже на новом раунде: если свежий вид ещё в пути, она ждёт его. */
  function пилюляСтарогоРаунда(ключЗапроса) {
    // Ушли из стола сети, стол у партии с ботами: пилюля про сетевой раунд ей не нужна.
    if (!поСети || Экран.режимСтола() !== 'сеть') return;
    if (ключЗапроса === ключРаунда) { пилюляЖдёт = true; return; }
    Экран.показатьПилюлю(ПИЛЮЛЯ_СТАРОГО_РАУНДА);
  }

  /* ---------- черновик: 400 мс тишины, последняя правка побеждает ---------- */

  function послатьЧерновик(раунд, черновик, ключЗапроса) {
    if (!window.Сеть || typeof window.Сеть.отправитьЧерновик !== 'function') return Promise.resolve(null);
    return window.Сеть.отправитьЧерновик(раунд, черновик).then(ответ => {
      сказатьОтказ(ответ, ключЗапроса);
      return ответ;
    });
  }

  /* Правка прошлого раунда сюда не доходит: новый раунд (и новая партия)
     забывает ждущую правку в показатьВид — забытьЖдущий(). */
  function отправитьЖдущий() {
    таймерЧерновика = null;
    const правка = ждущий;
    ждущий = null;
    if (!правка || партияЗакончена()) return Promise.resolve(null);   // после конца партии черновик не шлём
    return послатьЧерновик(правка.раунд, правка.черновик, ключРаунда);
  }

  function черновикИзменён(черновик) {
    if (молчим || !поСети || партияЗакончена()) return;
    убратьИтогПриДействии();   // правка черновика — первое действие в новом раунде
    ждущий = { раунд: раундСейчас(), черновик: черновик };
    clearTimeout(таймерЧерновика);
    таймерЧерновика = setTimeout(отправитьЖдущий, Правила.ЧИСЛА.задержкаЧерновикаМс);
  }

  function забытьЖдущий() {
    clearTimeout(таймерЧерновика);
    таймерЧерновика = null;
    ждущий = null;
  }

  /* ---------- «Готово» и «Изменить»: один ход в пути ---------- */

  function молча(дело) {
    молчим = true;
    try { дело(); } finally { молчим = false; }
  }

  /** Пока ход летит или партия кончилась, панель заперта: стол открывает кнопки при каждой перерисовке, запираем снова. */
  function замокКнопки() {
    const кнопка = $('захват-готово');
    // Во время раскрытия на месте «Готово» — «Пропустить ›» (ТЗ 8.4): он ничего не шлёт серверу, поэтому
    // летящий ход его не запирает, иначе он остался бы мёртвым все 8 секунд.
    const летящийХодЗапирает = ходВПути !== null && раскрытие === null;
    if ((летящийХодЗапирает || партияЗакончена()) && кнопка) кнопка.setAttribute('disabled', '');
    const отмена = $('захват-отменить');
    if (партияЗакончена() && отмена) отмена.setAttribute('disabled', '');
  }

  /** Касание после конца партии: стол уже перещёлкнул ✓ — возвращаем его к виду сервера, на сервер ничего не идёт. */
  function вернутьСтолКВиду() {
    if (итогНаЭкране()) поставитьКонечнуюКарту();   // итог уже показан: стол — конечная карта, не черновик
    else if (стол && сетевой && сетевой.захват) поставитьРаунд(сетевой.захват);
    замокКнопки();
  }

  function начатьПолёт() {
    номерХода++;
    ходВПути = номерХода;
    замокКнопки();
    return номерХода;
  }

  /** Ход долетел. Новый раунд мог уже снять этот полёт (или летит следующий) — тогда не трогаем. */
  function закончитьПолёт(полёт) {
    if (ходВПути !== полёт) return;
    ходВПути = null;
    // Стол сам решает, открыта ли кнопка (в игре ли я): перерисовываем его по последнему виду.
    if (стол && сетевой && сетевой.захват) стол.обновитьПартию(партияНаКарте(сетевой.захват), инфоИзВида(сетевой.захват));
    сверитьГотовность();
  }

  /** «Готово» стола: сперва черновик целиком (сервер берёт приказы из него), потом ход. */
  function готовоНажато(черновик) {
    if (молчим || !поСети) return;
    if (партияЗакончена()) { вернутьСтолКВиду(); return; }
    // Ещё летит «Изменить»: «Готово» его не обгоняет — стол возвращаем как был, на сервер ничего не идёт.
    if (ходВПути !== null) { молча(() => { if (стол.готов()) стол.изменить(); }); замокКнопки(); return; }
    закрытьЛистОстатка();
    забытьЖдущий();
    убратьИтогПриДействии();
    const раунд = раундСейчас();
    const ключ = ключРаунда;
    const полёт = начатьПолёт();
    return послатьЧерновик(раунд, черновик, ключ).then(ответ => {
      if (!ответ || !ответ.принято) return null;
      return window.Сеть.отправитьХод({ действие: 'готово', раунд: раунд }).then(итог => {
        сказатьОтказ(итог, ключ);
        return итог;
      });
    }).then(итог => {
      // Не дошло — человек снова правит черновик; отказ уже сказан словами.
      // Только в том же раунде: ✓ нового раунда — уже другое «Готово».
      if ((!итог || !итог.принято) && ключ === ключРаунда) молча(() => { if (стол.готов()) стол.изменить(); });
      закончитьПолёт(полёт);
    });
  }

  function изменитьНажато() {
    if (молчим || !поСети) return;
    if (партияЗакончена()) { вернутьСтолКВиду(); return; }
    // «Изменить» не обгоняет летящее «Готово»: стол возвращаем к ✓, на сервер ничего не идёт.
    if (ходВПути !== null) { молча(() => { if (!стол.готов()) стол.нажатьГотово(); }); замокКнопки(); return; }
    const ключ = ключРаунда;
    const полёт = начатьПолёт();
    return window.Сеть.отправитьХод({ действие: 'изменить', раунд: раундСейчас() }).then(итог => {
      сказатьОтказ(итог, ключ);
      закончитьПолёт(полёт);
    });
  }

  /* Лист «Осталось N войск. Поставить…?» — свой, с другими id, чем у партии
     с ботами: её экран ищет свой лист по id и не должен найти этот. */
  function листОстатка() {
    let лист = $('захват-онлайн-остаток');
    if (лист) return лист;
    лист = document.createElement('div');
    лист.id = 'захват-онлайн-остаток';
    лист.className = 'захват-лист скрыт';
    лист.setAttribute('role', 'dialog');
    лист.setAttribute('aria-labelledby', 'захват-онлайн-остаток-вопрос');
    // Серая строка сверху: «Вы нажали «Готово», но расставили не все войска». Слова приходят от стола.
    const пояснение = document.createElement('p');
    пояснение.id = 'захват-онлайн-остаток-пояснение';
    пояснение.className = 'захват-тихо';
    const вопрос = document.createElement('h2');
    вопрос.id = 'захват-онлайн-остаток-вопрос';
    const да = document.createElement('button');
    да.id = 'захват-онлайн-остаток-да';
    да.className = 'кнопка кнопка--главная';
    да.setAttribute('type', 'button');
    const нет = document.createElement('button');
    нет.id = 'захват-онлайн-остаток-нет';
    нет.className = 'кнопка';
    нет.setAttribute('type', 'button');
    лист.append(пояснение, вопрос, да, нет);
    $('экран-игры').appendChild(лист);
    да.addEventListener('click', () => { закрытьЛистОстатка(); стол.поставитьОстатокИГотово(); });
    нет.addEventListener('click', () => { закрытьЛистОстатка(); стол.отказатьсяОтВопроса(); });
    return лист;
  }

  function закрытьЛистОстатка() {
    const лист = $('захват-онлайн-остаток');
    if (лист) лист.classList.add('скрыт');
  }

  const поставлено = черновик => Object.keys(черновик.расстановка).reduce((сумма, к) => сумма + черновик.расстановка[к], 0);

  /** После «Готово»: стол спросил про остаток подкрепления — показываем вопрос листом. */
  // Слушатель стола уже пропустил раскрытие, а этот слушатель идёт следом на тот же щелчок и видит уже «обычный» стол.
  // Метка живёт доли секунды: касание карты тоже пропускает, но настоящий следующий щелчок «Готово» бывает позже.
  const ЖИЗНЬ_МЕТКИ_ПРОПУСКА_МС = 50;
  let пропускСлучилсяВ = -Infinity;
  function отметитьПропуск() {
    пропускСлучилсяВ = Date.now();
  }

  function спроситьОбОстатке() {
    // Это был «Пропустить ›», а не «Готово»: про остаток не спрашиваем.
    if (Date.now() - пропускСлучилсяВ < ЖИЗНЬ_МЕТКИ_ПРОПУСКА_МС) { пропускСлучилсяВ = -Infinity; return; }
    if (!поСети || Экран.режимСтола() !== 'сеть') return;   // стол слушает партию с ботами — у неё свой лист
    if (!стол || стол.готов() || !сетевой || !сетевой.захват) return;
    if (партияЗакончена()) { вернутьСтолКВиду(); return; }   // партия кончилась: вопрос про остаток не задаём
    const з = сетевой.захват;
    const партия = партияИзВида(з);
    if (!Правила.вИгре(партия, з.я)) return;
    const черновик = стол.черновик();
    if (!Правила.проверитьЧерновик(партия, з.я, черновик).принято) return;
    if ((партия.подкрепление[з.я] || 0) - поставлено(черновик) <= 0) return;
    const лист = листОстатка();
    // Слова строк и кнопок берём у стола; вопрос с именем области стол уже написал в подсказке.
    const слова = стол.вопросОбОстатке() || {};
    $('захват-онлайн-остаток-пояснение').textContent = слова.пояснение || '';
    $('захват-онлайн-остаток-вопрос').textContent = $('захват-подсказка').textContent;
    $('захват-онлайн-остаток-да').textContent = слова.кнопкаДа || '';
    $('захват-онлайн-остаток-нет').textContent = слова.кнопкаНет || '';
    лист.classList.remove('скрыт');
  }

  /* ---------- выход из стола: «‹», «В меню», «Сдаться» ---------- */

  /** «Да, сдаться» за сетевым столом: сдача уходит серверу, партия с ботами её не видит. */
  function сдаться() {
    if (!поСети || партияЗакончена() || !window.Сеть || typeof window.Сеть.отправитьХод !== 'function') return Promise.resolve(null);
    const ключ = ключРаунда;
    return window.Сеть.отправитьХод({ действие: 'сдаться' }).then(ответ => {
      сказатьОтказ(ответ, ключ);
      return ответ;
    });
  }

  /* Слова подтверждения ухода (ТЗ 3.8–3.9): вдвоём уход кончает партию,
     втроём и больше место водит бот. Строка листа и кнопки — как у домино. */
  const СЛОВА_УХОДА = { строка: 'Выйти из партии', заголовок: 'Выйти из партии?', да: 'Выйти', нет: 'Остаться' };
  const УХОД_ВДВОЁМ = 'Партия закончится.';
  const УХОД_С_БОТОМ = 'Ваше место займёт бот.';

  /**
   * Слова для окна «Выйти из партии?» или null — спрашивать не о чем и «‹»
   * выходит сразу: партия по виду сервера не идёт (конец) или я уже вне игры
   * (выбыл, сдался) — тогда уход ничего не меняет и обещать «место займёт бот» нечестно.
   */
  function словаВыхода() {
    if (!поСети || !сетевой || !сетевой.захват) return null;
    if (сетевой.этап !== 'игра' || сетевой.завершена === true) return null;
    const з = сетевой.захват;
    if (!Правила.вИгре(партияИзВида(з), з.я)) return null;
    return Object.assign({ текст: живыхЛюдей(з) <= 2 ? УХОД_ВДВОЁМ : УХОД_С_БОТОМ }, СЛОВА_УХОДА);
  }

  /**
   * Живой человек — как в правилах (причинаКонца): не бот стола, не ушёл, не выбыл, не сдался.
   * Спящий (сервер ставит ему и «бот», и «спит») — по-прежнему человек: за него ходит бот лишь пока он молчит.
   * Ушедшего сервер сам помечает ботом (комнаты.js, выйти) и «ушёл», так что считаем по обоим.
   * Людей двое или меньше — уход последнего соперника кончает партию, а не отдаёт место боту.
   */
  function живыхЛюдей(з) {
    return з.игроки.filter(и => (!и.этоБот || и.спит) && !и.ушёл && !и.выбыл && !и.сдался).length;
  }

  /** «‹» и «В меню» за сетевым столом (после подтверждения): выйти из стола сети и вернуться в лобби. */
  function выйтиИзСтола() {
    if (window.Сеть && typeof window.Сеть.покинутьПартию === 'function') window.Сеть.покинутьПартию();
    вМеню();
  }

  function вМеню() {
    сбросить();
    поСети = false;
    Экран.отпуститьСтол();
    экран('экран-лобби');
  }

  /* ---------- стол из вида ---------- */

  // Слушатели общего стола и двери выхода — экран зовёт их, пока стол в режиме «сеть».
  const ДВЕРИ_СЕТИ = {
    приИзменении: черновикИзменён,
    приГотово: готовоНажато,
    приИзменить: изменитьНажато,
    приВиде: вид => { видКарты = вид; нарисоватьКартуПоКадру(); },
    // Стол шлёт { из, x, y } пока палец тянет приказ и null, когда отпустил или отменил: стрелку рисует карта-вид.
    приПротяжке: данные => {
      протяжкаПальцем = данные ? { откуда: данные.из, x: данные.x, y: данные.y } : null;
      нарисоватьКартуПоКадру();
    },
    // Игрок сменил «Эффекты стекла» в листе «⋯» за сетевым столом: набор рисунков перегружается.
    приСменеЭффектов: () => {
      if (!сетевой || !сетевой.захват) return;
      подготовитьРисунки(партияИзВида(сетевой.захват));
      нарисоватьКарту();
    },
    // Узел карты поменял размер: слой стол уже пересчитал (экран), холст — по новому месту карты.
    приСменеРазмера: () => нарисоватьКарту(),
    // Выбор, приказ или цель новичка поменялись — холст рисует «своё» заново (стол отдаёт его параметрыХолста).
    приСменеХолста: () => нарисоватьКартуПоКадру(),
    // Первое касание карты после итога раунда — итог своё отработал.
    приКасанииКарты: убратьИтогПриДействии,
    приОтказе: () => { const звук = window.ЗахватЗвук; if (звук && typeof звук.отказ === 'function') звук.отказ(); },
    // «Пропустить ›» или касание карты во время раскрытия (стол зовёт сам). Пропуск — только у себя на экране:
    // раскрытие у всех идёт по часам сервера (ТЗ 8.5), на сервер пропуск не уходит и «Готово» не ставит.
    приПропуске: () => { отметитьПропуск(); return пропуститьРаскрытие(); },
    // Касание пластины: во время раскрытия — пропуск (true: журнал не открывать), иначе экран открывает журнал онлайна.
    приКасанииПластины: () => пропуститьРаскрытие(),
    выйти: выйтиИзСтола,
    словаВыхода: словаВыхода,
    сдаться: сдаться,
    // Долгое касание своей области при остатке: лист «Поставить сюда» сети.
    приДолгомКасанииСОстатком: область => открытьПоставитьСюда(область),
    // «Ещё партия» окна итога.
    'ещё': () => ещёНажато()
  };

  /** Общий стол страницы в режиме «сеть»: партию с ботами экран при этом откладывает. */
  function достатьСтол() {
    стол = Экран.столДляСети(ДВЕРИ_СЕТИ);
    if (!слушаемОстаток) {
      слушаемОстаток = true;
      // Стол слушает «Готово» сам; этот слушатель идёт после него и видит, что стол спросил про остаток.
      $('захват-готово').addEventListener('click', спроситьОбОстатке);
    }
    return стол;
  }

  /** Поставить раунд из вида: черновик — с сервера, ✓ — как у сервера. */
  function поставитьРаунд(з) {
    const с = достатьСтол();
    молча(() => {
      // Стол ушёл к партии с ботами посреди раскрытия и вернулся: его ставят заново, а раскрытие ещё идёт —
      // стол должен знать об этом, иначе касание карты не пропустит показ.
      с.задатьРаскрытие(раскрытие !== null);
      протяжкаПальцем = null;   // новый раунд посреди протяжки: стрелка за пальцем не должна остаться висеть
      с.начатьРаунд(партияНаКарте(з), з.я, инфоИзВида(з), черновикИзВида(з));
      if (з.яГотов) {
        const ответ = с.нажатьГотово();
        // Сервер ставит остаток по тому же правилу 3.3 — повторяем, чтобы ✓ сошлась.
        if (ответ && ответ.вопрос) с.поставитьОстатокИГотово();
      }
    });
    с.показатьСлой(ширинаКарты());
  }

  /** ✓ на экране и на сервере разошлись (другое устройство, отказ) — верим серверу. */
  function сверитьГотовность() {
    if (ходВПути !== null || !стол || !сетевой || !сетевой.захват) return;
    if (итогНаЭкране()) return;   // после итога на столе конечная карта: ✓ сверять не с чем
    if (!!сетевой.захват.яГотов === стол.готов()) return;
    // Посреди раскрытия стол не пересоздаём (это снимет всплытия и сбросит зум): обновляем только отметки ✓.
    // Свою готовность сверит следующий раунд.
    if (раскрытие !== null) { столПоВиду(); return; }
    поставитьРаунд(сетевой.захват);
  }

  /* ---------- таймер раунда (ТЗ 3.6) ----------
     Сервер шлёт «сколько миллисекунд осталось», а не время на часах (часы телефонов
     врут): срок считаем от часов телефона в миг прихода вида. Таймер идёт и во время
     раскрытия (решение штаба 01.10): сервер уже считает следующий раунд. */

  const узелТаймера = () => $('захват-таймер');

  /** Секунд до конца, округляя вверх: «0:01» держится до самого нуля. */
  function секундДоКонца() {
    return Math.max(0, Math.ceil((срокРаунда - Date.now()) / 1000));
  }

  function подписьТаймера(секунд) {
    const остаток = секунд % 60;
    return Math.floor(секунд / 60) + ':' + (остаток < 10 ? '0' : '') + остаток;
  }

  /** Стол ушёл к партии с ботами мимо нас («Играть с ботами», «Продолжить»): чужой отсчёт над ним не нужен. */
  const столУСети = () => Экран.режимСтола() === 'сеть';

  function нарисоватьТаймер(секунд) {
    const узел = узелТаймера();
    if (!узел) return;
    if (!столУСети()) { снятьТаймер(); return; }
    узел.textContent = подписьТаймера(секунд);
    узел.classList.remove('скрыт');
    узел.classList.toggle(КЛАСС_ТАЙМЕРА_МАЛО, секунд <= ПОСЛЕДНИЕ_СЕКУНДЫ);
  }

  function остановитьИнтервалТаймера() {
    if (интервалТаймера !== null) clearInterval(интервалТаймера);
    интервалТаймера = null;
  }

  /** Тик раз в секунду; звук — только в последние секунды, а выключатель звука смотрит сам ЗахватЗвук. */
  function тикТаймера() {
    if (!столУСети()) { снятьТаймер(); return; }
    const секунд = секундДоКонца();
    нарисоватьТаймер(секунд);
    const звук = window.ЗахватЗвук;
    if (секунд > 0 && секунд <= ПОСЛЕДНИЕ_СЕКУНДЫ && звук && typeof звук.тик === 'function') звук.тик();
    if (секунд === 0) остановитьИнтервалТаймера();   // время вышло: ждём вид с новым раундом
  }

  function снятьТаймер() {
    остановитьИнтервалТаймера();
    срокРаунда = null;
    const узел = узелТаймера();
    if (!узел) return;
    узел.textContent = '';
    узел.classList.remove(КЛАСС_ТАЙМЕРА_МАЛО);
    узел.classList.add('скрыт');
  }

  /** Новый вид — новый срок. Нет времени в виде (партия кончилась, мсДоКонца пуст) — таймера нет. */
  function поставитьТаймер(з) {
    const мс = з.мсДоКонца;
    if (партияЗакончена() || typeof мс !== 'number' || !isFinite(мс) || !узелТаймера()) { снятьТаймер(); return; }
    остановитьИнтервалТаймера();
    срокРаунда = Date.now() + мс;
    нарисоватьТаймер(секундДоКонца());
    интервалТаймера = setInterval(тикТаймера, 1000);
  }

  /** Окно «Выйти из партии?» могло быть открыто, пока партия кончилась сама: закрываем его дверью экрана (паузу она не снимает). */
  function закрытьОкноВыхода() {
    if (typeof Экран.закрытьОкноВыхода === 'function') Экран.закрытьОкноВыхода();
  }

  /* ---------- раскрытие раунда и журнал (ТЗ 8.5, 3.1) ----------
     Новый разбор узнаётся по смене раундСобытий. Раскрытие — только показ: сервер
     уже открыл следующий раунд, поэтому черновик, «Готово» и таймер раунда во время
     него работают (ТЗ 3.1, решение штаба 01.10). Касание карты или пластины — пропуск. */

  const номерПартии = вид => Number(вид.сыграноПартий) || 0;

  // Последний РАЗОБРАННЫЙ раунд журнала. Запись с одними фразами (В10) ждёт разбора: она не значит
  // «раунд уже записан» и не делает журнал «чужим» (раунд новее разбора сервера).
  const разобранВЖурнале = запись => (window.ЗахватПамять && typeof window.ЗахватПамять.раундРазобран === 'function'
    ? window.ЗахватПамять.раундРазобран(запись) : true);
  function последнийРаундЖурнала(ж) {
    const разобранные = ж ? ж.раунды.filter(разобранВЖурнале) : [];
    return разобранные.length ? разобранные[разобранные.length - 1].номер : 0;
  }

  /**
   * Журнал онлайна — один на партию. Тот же стол и та же партия (перезагрузка) — журнал целый, не затираем.
   * Коды комнат переиспользуются: раунд в журнале новее последнего разбора сервера — журнал чужого стола.
   */
  function начатьЖурналПартии(вид) {
    if (!Память) return;
    const з = вид.захват;
    const разобрано = typeof з.раундСобытий === 'number' ? з.раундСобытий : Math.max(0, (Number(з.раунд) || 1) - 1);
    const ж = Память.прочитатьЖурнал(РЕЖИМ_ЖУРНАЛА);
    const свой = ж && ж.стол === String(вид.код) && ж.партия === номерПартии(вид);
    if (свой && последнийРаундЖурнала(ж) <= разобрано) return;
    Память.начатьЖурнал(вид.код, номерПартии(вид), РЕЖИМ_ЖУРНАЛА);
    показанныйРазбор = null;   // разбор чужого стола с тем же кодом — не «уже показанный»
    // Новая комната с тем же кодом считает знаки заново с 1: ключ «К7:1» прошлого стола — не повтор.
    записанныеФразы.clear();
  }

  /** Раунд в журнал ровно один раз: после перезагрузки сервер шлёт тот же разбор снова, а модуль его уже не помнит. */
  function записатьРаундЖурнала(номер, строки) {
    if (!Память) return;
    const ж = Память.прочитатьЖурнал(РЕЖИМ_ЖУРНАЛА);
    if (номер <= последнийРаундЖурнала(ж)) return;
    Память.добавитьРаундЖурнала(номер, строки, РЕЖИМ_ЖУРНАЛА);
  }

  /**
   * Карта до разбора («край взят» и шаги раскрытия). Сервер шлёт её сам (хозяеваДо);
   * у старых партий её нет — берём хозяев прошлого вида той же партии, снятого в раунде
   * разбора. Нет и его (перезагрузка, вход посреди партии) — null.
   */
  function картаДоРазбора(вид, прошлый) {
    const з = вид.захват;
    if (Array.isArray(з.хозяеваДо)) return з.хозяеваДо.slice();
    const пз = прошлый && прошлый.захват;
    const таЖеПартия = !!пз && прошлый.код === вид.код && номерПартии(прошлый) === номерПартии(вид);
    if (таЖеПартия && пз.раунд === з.раундСобытий && Array.isArray(пз.хозяева)) return пз.хозяева.slice();
    return null;
  }

  /**
   * Войска до разбора: сервер их не шлёт, берём из прошлого вида той же партии и того же раунда.
   * Нет его (перезагрузка) — null: шайбы во время раскрытия покажут войска после боёв.
   */
  function войскаДоРазбора(вид, прошлый) {
    const пз = прошлый && прошлый.захват;
    if (!пз || прошлый.код !== вид.код || номерПартии(прошлый) !== номерПартии(вид)) return null;
    if (пз.раунд !== вид.захват.раундСобытий || !Array.isArray(пз.войска)) return null;
    return пз.войска.slice();
  }

  /**
   * Сервер считает 8 с показа в мсДоКонца (мсДоКонца = показ + секундНаРаунд сразу после разбора).
   * Осталось не больше длины раунда — показ уже прошёл (перезагрузка, поздний вход): шаги не проигрываем.
   */
  function показУжеПрошёл(з) {
    return typeof з.секундНаРаунд === 'number' && typeof з.мсДоКонца === 'number' && з.мсДоКонца <= з.секундНаРаунд * 1000;
  }

  /** Показ прошлого разбора больше не к месту (новая партия, первый раунд): часы сняты, его пластина спрятана. */
  function бросьПоказРазбора() {
    if (раскрытие === null && таймерИтогаРаунда === null) return;
    остановитьРаскрытие();
    убратьИтог();
  }

  /** Вид принёс разбор, которого ещё не показывали: журнал, затем раскрытие (или одна пластина итога). */
  function показатьРазбор(вид, прошлый) {
    const з = вид.захват;
    // Разбора в виде нет (первый раунд, реванш посреди раскрытия) — показ прошлой партии над новой не нужен.
    if (typeof з.раундСобытий !== 'number') { бросьПоказРазбора(); return; }
    // Событий нет — и этот разбор не показать: прошлый показ над новым видом тоже не нужен.
    if (!Array.isArray(з.события) || !window.ЗахватРаскрытие) { бросьПоказРазбора(); return; }
    const ключ = [вид.код, номерПартии(вид), з.раундСобытий].join('|');
    if (ключ === показанныйРазбор) return;   // тот же разбор пришёл снова (чужой ✓, новая версия) — не повторяем
    показанныйРазбор = ключ;
    const хозяеваДо = картаДоРазбора(вид, прошлый);
    let расписание;
    try {
      расписание = window.ЗахватРаскрытие.построить({
        события: з.события, раунд: з.раундСобытий, карта: з.карта, имена: инфоИзВида(з).имена,
        я: з.я, хозяеваДо: хозяеваДо, хозяеваПосле: з.хозяева
      });
    } catch (ошибка) {
      console.warn('Захват по сети: раскрытие раунда не построено', ошибка);
      return;
    }
    записатьРаундЖурнала(з.раундСобытий, расписание.журнал);
    // Показ уже прошёл: стол просто встаёт в конечную карту (её рисует показатьВид следом), без пластины.
    if (показУжеПрошёл(з)) { бросьПоказРазбора(); return; }
    // Без карты «до» шаги показали бы неправду про захваты — хватит итога раунда.
    if (хозяеваДо) начатьРаскрытие(расписание, хозяеваДо, войскаДоРазбора(вид, прошлый));
    else показатьИтогРаунда(расписание.итог, расписание.подписиИтога, расписание.подвалИтога);
  }

  // Эффекты раскрытия на карте (стрелки, капли, вспышки, трещина, налив): та же копия, что у партии с ботами,
  // на том же расписании. Сервер про них ничего не знает.
  const эффектыРаскрытия = Экран.создатьЭффектыРаскрытия(() => лёгкийНабор, () => сетевой && сетевой.захват && сетевой.захват.карта);
  let кадрЭффектовЖдёт = false;

  /** Таймеры расписания и эффекты на карте — одни часы: снимаются вместе (конец, пропуск, выход, сброс). */
  function снятьТаймерыРаскрытия() {
    таймерыРаскрытия.forEach(номер => clearTimeout(номер));
    таймерыРаскрытия = [];
    эффектыРаскрытия.очистить();
    // «+N/−N» раскрытия — тоже его часы; всплытия партии с ботами (стол ушёл к ней) не трогаем.
    if (стол && столУСети()) стол.снятьВсплытия();
  }

  /** Эффект шага: сразу перерисовать, а пока он движется — рисовать каждый кадр. Не эффект — ответ false. */
  function показатьЭффектШага(шаг) {
    if (!эффектыРаскрытия.добавитьШаг(шаг)) return false;
    нарисоватьКарту();
    крутитьКадрыЭффектов();
    return true;
  }

  /** Без requestAnimationFrame (node) кадров нет: карта рисуется только на шагах. */
  function крутитьКадрыЭффектов() {
    if (кадрЭффектовЖдёт || typeof window.requestAnimationFrame !== 'function' || !эффектыРаскрытия.идут()) return;
    кадрЭффектовЖдёт = true;
    window.requestAnimationFrame(() => {
      кадрЭффектовЖдёт = false;
      if (!раскрытие) return;
      нарисоватьКарту();
      // Эффекты отыграли после этого кадра: он поймал вспышку на излёте — рисуем последний, чистый кадр,
      // иначе она так и застынет на карте.
      if (эффектыРаскрытия.идут()) крутитьКадрыЭффектов();
      else нарисоватьКарту();
    });
  }

  /** Стол — по последнему виду: до итоговой карты партия «до», после — конечная (партияНаКарте решает сама). */
  function столПоВиду() {
    if (!стол || !столУСети() || !сетевой || !сетевой.захват) return;
    стол.обновитьПартию(партияНаКарте(сетевой.захват), инфоИзВида(сетевой.захват));
    замокКнопки();   // стол открывает панель по своим правилам; конец партии и летящий ход держат её запертой
  }

  function начатьРаскрытие(расписание, хозяеваДо, войскаДо) {
    остановитьРаскрытие();
    раскрытие = { итог: расписание.итог, подвал: расписание.подвалИтога, подписи: расписание.подписиИтога || [], шагов: расписание.шаги.length,
      хозяеваДо: хозяеваДо, войскаДо: войскаДо || null, итоговаяКарта: false };
    if (стол) стол.задатьРаскрытие(true);
    // Шайбы стола — тоже «до»: итоговые хозяева и войска появятся только на шаге итоговой карты.
    столПоВиду();
    расписание.шаги.forEach(шаг => { таймерыРаскрытия.push(setTimeout(() => сделатьШаг(шаг), шаг.с)); });
    таймерыРаскрытия.push(setTimeout(закончитьРаскрытие, расписание.всегоМс));
  }

  /** Шаг расписания. Стрелки, капли, вспышка, трещина и налив рисует карта; «+N» и «−N» всплывает стол (как у ботов). */
  function сделатьШаг(шаг) {
    // Стол ушёл к партии с ботами мимо нас: ни звука, ни пластины над её картой.
    if (!столУСети()) { остановитьРаскрытие(); return; }
    if (шаг.вид === 'плюс' || шаг.вид === 'минус') {
      if (стол) стол.всплытие(шаг.область, шаг.текст, шаг.вид === 'минус' ? -1 : 1, шаг.длит);
      return;
    }
    if (шаг.вид === 'звук') {
      // Выключатель звука смотрит сам ЗахватЗвук.
      const звук = window.ЗахватЗвук;
      if (звук && typeof звук[шаг.имя] === 'function') звук[шаг.имя]();
      return;
    }
    if (шаг.вид === 'пластина') { Экран.показатьПластину([шаг.текст]); return; }
    if (шаг.вид === 'итоговая-карта') {
      эффектыРаскрытия.очистить();   // итоговая карта чистая: стрелки и вспышки уже отыграли
      раскрытие.итоговаяКарта = true;
      столПоВиду();
      нарисоватьКарту();
      return;
    }
    if (шаг.вид === 'итог-раунда') { показатьПластинуИтога(шаг.строки, шаг.подписи, шаг.подвал); return; }
    показатьЭффектШага(шаг);
  }

  function закончитьРаскрытие() {
    снятьТаймерыРаскрытия();
    if (!раскрытие) return;
    раскрытие = null;
    if (!столУСети()) return;
    if (стол) стол.задатьРаскрытие(false);
    столПоВиду();   // раскрытия больше нет: на столе конечная партия, даже если шаг итоговой карты не наступил
    держатьИтог();
    показатьИтогЕслиПора();   // раскрытие последнего раунда досмотрено — теперь итог партии
    нарисоватьКарту();   // эффекты сняты, хозяева конечные: последний кадр раскрытия на холсте не остаётся
  }

  /** Касание карты или пластины во время раскрытия: сразу конечная карта и итог раунда. Ответ — было ли что пропускать. */
  function пропуститьРаскрытие() {
    if (!раскрытие) return false;
    const итог = раскрытие.итог;
    const подписи = раскрытие.подписи;
    const подвал = раскрытие.подвал;
    снятьТаймерыРаскрытия();
    раскрытие.итоговаяКарта = true;   // пропуск — сразу итоговая карта, не «до»
    нарисоватьКарту();
    показатьПластинуИтога(итог, подписи, подвал);
    закончитьРаскрытие();
    return true;
  }

  /** Пластина итога без шагов: карты «до» нет. */
  function показатьИтогРаунда(строки, подписи, подвал) {
    остановитьРаскрытие();
    показатьПластинуИтога(строки, подписи, подвал);
    держатьИтог();
  }

  /**
   * Пластина итога раунда и имена областей из неё на карте (ТЗ 8.4.1): уходят вместе.
   * Подвал «Раунд N · Журнал ›» (ТЗ 8.5) — последняя строка, как у партии с ботами; журнал онлайна открывает касание пластины.
   */
  function показатьПластинуИтога(строки, подписи, подвал) {
    Экран.показатьПластину(typeof подвал === 'string' && подвал ? строки.concat(подвал) : строки);
    if (стол && столУСети()) стол.показатьПодписи(подписи);
  }

  /** Убрать пластину итога и подписи областей; часы держания снять. */
  function убратьИтог() {
    clearTimeout(таймерИтогаРаунда);
    таймерИтогаРаунда = null;
    Экран.спрятатьПластину();   // у партии с ботами дверь ничего не делает
    if (стол && столУСети()) стол.снятьПодписи();
  }

  /** Итог раунда держится в новом раунде до первого действия игрока, но не дольше 10 с (ТЗ 8.5). */
  function держатьИтог() {
    clearTimeout(таймерИтогаРаунда);
    таймерИтогаРаунда = setTimeout(() => {
      таймерИтогаРаунда = null;
      if (столУСети()) убратьИтог();
      else Экран.спрятатьПластину();   // стол ушёл к ботам: подписи не трогаем, пластину просим спрятать (дверь экрана за столом ботов может промолчать)
    }, ДЕРЖАТЬ_ИТОГ_МС);
  }

  /** Первое действие игрока (касание карты, правка черновика, «Готово») — итог своё отработал. */
  function убратьИтогПриДействии() {
    if (таймерИтогаРаунда !== null) убратьИтог();
  }

  /** Снять все часы раскрытия (выход, сброс). Стол возвращаем из раскрытия, только пока он у сети. */
  function остановитьРаскрытие() {
    снятьТаймерыРаскрытия();
    clearTimeout(таймерИтогаРаунда);
    таймерИтогаРаунда = null;
    const шло = раскрытие !== null;
    раскрытие = null;
    if (шло && стол && столУСети()) {
      стол.задатьРаскрытие(false);
      столПоВиду();   // раскрытие брошено на середине: на столе не должна остаться партия «до»
    }
  }

  /* ---------- конец партии: рекорд, итог, «Ещё партия» (ТЗ 8.7, 3.9) ----------
     Рекорд пишется в миг первого вида с концом — до показа, как у ботов: закрыть
     страницу посреди раскрытия ничего не потеряет. Окно итога — после раскрытия
     последнего раунда (или сразу, если раскрытия нет). */

  const ключПартииВида = вид => [вид.код, номерПартии(вид)].join('|');

  /* Отметки итогов в памяти телефона (zahvat-online-done): защёлка в странице
     после перезагрузки пуста, а отметка остаётся. Рекорд метят ключом партии,
     звук — ключом с припиской: рекорд пишется до раскрытия, звук — после, и
     перезагрузка между ними не должна съесть звук. Старая память без отметок
     (разъезд кэша) — работаем на одной защёлке страницы. */
  const МЕТКА_ЗВУКА = '|звук';
  const отмеченоВПамяти = метка => !!Память && typeof Память.итогЗаписан === 'function' && Память.итогЗаписан(метка);
  function отметитьВПамяти(метка) {
    if (Память && typeof Память.отметитьИтог === 'function') Память.отметитьИтог(метка);
  }

  /** Партия не засчитана (ТЗ 3.9): сервер сказал сам или прислал конец без итога (старый сервер без поля «отменена»). */
  function партияОтменена(з) {
    if (з.отменена === true) return true;
    return !з.итог || !Array.isArray(з.итог.места) || з.итог.места.length === 0;
  }

  /** Моя строка в таблице мест; нет её — null. */
  function мояСтрока(з) {
    if (!з.итог || !Array.isArray(з.итог.места)) return null;
    return з.итог.места.find(с => с.кто === з.я) || null;
  }

  const яВПлюсе = з => !!(з.итог && Array.isArray(з.итог.победители) && з.итог.победители.indexOf(з.я) !== -1);

  /** Рекорд партии — ровно один раз на код|партию: ни повторный вид с концом, ни перезагрузка его не повторят. */
  function записатьРекордПартии(вид) {
    const ключ = ключПартииВида(вид);
    if (записанныйРекорд === ключ) return;
    const з = вид.захват;
    if (партияОтменена(з)) return;   // отменённая партия рекорда не даёт
    const мой = мояСтрока(з);
    if (!мой || !Память) return;
    записанныйРекорд = ключ;
    if (отмеченоВПамяти(ключ)) return;   // рекорд лёг ещё до перезагрузки страницы
    const таблица = Память.добавитьРекорд({
      когда: Date.now(), режим: РЕЖИМ_РЕКОРДА, мест: з.игроки.length,
      место: мой.место, очки: мой.очки, раундов: Number(з.итог.раунд) || з.раунд
    });
    // Память не приняла строку (null — негодная строка): отметку не ставим, рекорда ведь нет.
    if (таблица) отметитьВПамяти(ключ);
  }

  /** H1 итога по моему месту (ТЗ 8.7). Слова без рода игрока (8.5а). */
  function заголовокКонца(з) {
    const мой = мояСтрока(з);
    if (!мой || мой.как !== 'живой') return 'Партия окончена';
    if (мой.место === 1) return 'Победа!';
    return мой.место + '-е место' + (яВПлюсе(з) ? ' — в плюсе' : '');
  }

  /** Причина серым под H1. Тексты свои: у правил «Все люди выбыли», а ТЗ 8.7 пишет «Люди выбыли». */
  function причинаКонца(з) {
    const итог = з.итог;
    if (итог.причина === 'столицы') {
      // Все столицы взял тот, кто первый в таблице мест: правила ставят его первым.
      const кто = итог.места[0].кто;
      return кто === з.я ? 'Все столицы ваши' : 'Все столицы у ' + (инфоИзВида(з).имена[кто] || 'Игрок');
    }
    if (итог.причина === 'раунды') return 'По очкам после ' + з.всегоРаундов + ' раундов';
    if (итог.причина === 'люди выбыли') return 'Люди выбыли';
    if (итог.причина === 'остальные выбыли') return 'Остальные выбыли';
    return итог.словами || '';
  }

  /** Другие люди за столом (не боты стола и не ушедшие): кого звать «соперник», а кого «соперники». */
  function другихЛюдей(з) {
    return з.игроки.filter(и => и.номер !== з.я && (!и.этоБот || и.спит) && !и.ушёл).length;
  }

  /** Строка под H1: отказ на «ещё», причина конца и (как у домино) зов соперника сыграть ещё. */
  function причинаВОкне(вид) {
    const з = вид.захват;
    if (отказЕщё) return отказЕщё;
    const причина = партияОтменена(з) ? ПРИЧИНА_ОТМЕНЫ : причинаКонца(з);
    if (вид.яХочуЕщё !== true && вид.соперникХочетЕщё === true) {
      return причина + (другихЛюдей(з) > 1 ? ' Соперники зовут сыграть ещё.' : ' Соперник зовёт сыграть ещё.');
    }
    return причина;
  }

  /** Данные для двери Экран.показатьИтог. У отменённой партии таблицы мест нет. */
  function данныеИтога(вид) {
    const з = вид.захват;
    const имена = инфоИзВида(з).имена;
    if (партияОтменена(з)) {
      return { места: [], победители: [], я: з.я, имена: имена, причина: '', словами: '',
        заголовок: ЗАГОЛОВОК_ОТМЕНЫ, причинаСловами: причинаВОкне(вид) };
    }
    const итог = з.итог;
    return {
      места: итог.места, победители: итог.победители || [], я: з.я, имена: имена,
      причина: итог.причина, словами: итог.словами || '',
      заголовок: заголовокКонца(з), причинаСловами: причинаВОкне(вид)
    };
  }

  /** Подпись и замок «Ещё партия» — по флагам комнаты, как у домино.
      Уход соперника важнее нашего «ещё»: иначе кнопка навсегда ждала бы ушедшего. */
  function кнопкиИтога(вид) {
    if (вид.соперникУшёл === true) return { ещё: ПОДПИСЬ_ЕЩЁ, ещёЗаперта: true };   // звать некого
    if (вид.яХочуЕщё === true || ещёПослано === ключПартииВида(вид)) return { ещё: ПОДПИСЬ_ЖДЁМ, ещёЗаперта: true };
    if (вид.соперникХочетЕщё === true) return { ещё: ПОДПИСЬ_СОГЛАСИТЬСЯ, ещёЗаперта: false };
    return { ещё: ПОДПИСЬ_ЕЩЁ, ещёЗаперта: false };
  }

  /** Звук конца — один раз на партию и после перезагрузки тоже; выключатель и вибрацию смотрит сам ЗахватЗвук (как у ботов). */
  function сыгратьЗвукКонца(з, ключ) {
    const звук = window.ЗахватЗвук;
    if (!звук || партияОтменена(з)) return;
    if (отмеченоВПамяти(ключ + МЕТКА_ЗВУКА)) return;   // уже звучал до перезагрузки
    отметитьВПамяти(ключ + МЕТКА_ЗВУКА);
    const имя = яВПлюсе(з) ? 'победа' : 'поражение';
    if (typeof звук[имя] === 'function') звук[имя]();
  }

  /**
   * Итог на экран, когда пора: партия кончилась, раскрытие последнего раунда
   * досмотрено (или пропущено), стол у сети. Первый показ — со звуком; повтор
   * вида только освежает окно и снова ставит конечную карту (сверка ✓ могла её сбить).
   */
  function показатьИтогЕслиПора() {
    if (!поСети || !партияЗакончена() || раскрытие !== null || !столУСети()) return;
    const вид = сетевой;
    const з = вид.захват;
    const ключ = ключПартииВида(вид);
    const первый = показанныйИтог !== ключ;
    показанныйИтог = ключ;
    закрытьПоставитьСюда();
    убратьИтог();   // пластина раунда и подписи областей — до окна итога партии
    поставитьКонечнуюКарту();
    if (первый) сыгратьЗвукКонца(з, ключ);
    Экран.показатьИтог(данныеИтога(вид), кнопкиИтога(вид));
  }

  /** Итог этой партии уже показан (окно открыто, стол — конечная карта). */
  const итогНаЭкране = () => !!сетевой && партияЗакончена() && показанныйИтог === ключПартииВида(сетевой);

  /** Конечная карта дверью экрана: приказов нет, панель заперта; холст рисует сеть. */
  function поставитьКонечнуюКарту() {
    const з = сетевой.захват;
    молча(() => Экран.показатьКонечнуюКарту(партияИзВида(з), з.я, инфоИзВида(з)));
    нарисоватьКарту();
  }

  /** Окно итога уже на экране — освежить его подписи (ответ на «ещё»). */
  function освежитьИтог() {
    if (!итогНаЭкране() || !столУСети()) return;
    Экран.показатьИтог(данныеИтога(сетевой), кнопкиИтога(сетевой));
  }

  /** Началась новая партия того же стола (или стол сменился): окно итога прошлой закрываем. */
  function забытьИтог() {
    if (показанныйИтог !== null) Экран.закрытьИтог();
    показанныйИтог = null;
    ещёПослано = null;
    отказЕщё = '';
  }

  /** «Ещё партия» окна итога (дверь 'ещё'): ход уходит один раз, кнопка ждёт согласия игроков. */
  function ещёНажато() {
    if (!поСети || !сетевой || !партияЗакончена()) return Promise.resolve(null);
    if (!window.Сеть || typeof window.Сеть.отправитьХод !== 'function') return Promise.resolve(null);
    const ключ = ключПартииВида(сетевой);
    if (ещёПослано === ключ || сетевой.яХочуЕщё === true) return Promise.resolve(null);
    ещёПослано = ключ;
    отказЕщё = '';
    освежитьИтог();
    return window.Сеть.отправитьХод({ действие: 'ещё' }).then(ответ => {
      if (ответ && ответ.принято) return ответ;   // дальше говорит вид: «хочу ещё» или новая партия
      // Отказ — кнопка снова открыта, причина словами; про чужую партию не говорим.
      if (ещёПослано !== ключ) return ответ;
      ещёПослано = null;
      отказЕщё = (ответ && ответ.причина) || '';
      освежитьИтог();
      return ответ;
    });
  }

  /* ---------- лист «Поставить сюда» (ТЗ 9, решение штаба А) ----------
     Свой лист с другими id, чем у партии с ботами (её экран ищет свой по id).
     Войска ставит стол.поставитьВойска — тот же путь черновика, что и касание:
     на сервер уходит черновик через 400 мс тишины, прямой отправки нет. */

