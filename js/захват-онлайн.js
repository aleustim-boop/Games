  function партияИзВида(з) {
    const игроки = з.игроки.slice().sort((а, б) => а.цвет - б.цвет);
    const подкрепление = {}, выбыли = {}, сдались = {}, ушлоВРаунде = {};
    игроки.forEach(и => {
      подкрепление[и.номер] = и.подкрепление;
      if (и.выбыл) выбыли[и.номер] = true;
      if (и.сдался) сдались[и.номер] = true;
      if (и.ушёл) ушлоВРаунде[и.номер] = з.раунд;
    });
    if (з.моёПодкрепление) подкрепление[з.я] = з.моёПодкрепление.всего;
    return {
      карта: з.карта,
      раунд: з.раунд,
      всегоРаундов: з.всегоРаундов,
      игроки: игроки.map(и => и.номер),
      хозяева: з.хозяева.slice(),
      войска: з.войска.slice(),
      столицы: з.столицы.map(с => ({ область: с.область, хозяинНаСтарте: с.хозяинНаСтарте })),
      подкрепление: подкрепление,
      выбыли: выбыли,
      сдались: сдались,
      ушлоВРаунде: ушлоВРаунде
    };
  }

