/* Клетки нумеруем числами от 0 до 63: номер = ряд * 8 + столбец.
   Ряд 0 — первая горизонталь (там стоят белые), ряд 7 — восьмая.
   Столбец 0 — вертикаль «a», столбец 7 — вертикаль «h».

   Наружу номера не выходят: снаружи поля называются по-человечески
   («e4», «h8»). Числа остались внутри, потому что доску удобно держать
   одним плоским списком: он копируется одной строчкой и сравнивается
   целиком, а копировать позицию придётся очень часто — боту на каждом
   шаге перебора. */
const БУКВЫ = 'abcdefgh';
const РЯДОВ = 8;
const СТОЛБЦОВ = 8;
const КЛЕТОК = РЯДОВ * СТОЛБЦОВ;

/** Номер клетки по ряду и столбцу. За доской — минус единица. */
function клетка(ряд, столбец) {
  if (ряд < 0 || ряд >= РЯДОВ || столбец < 0 || столбец >= СТОЛБЦОВ) return -1;
  return ряд * СТОЛБЦОВ + столбец;
}

function рядКлетки(номер) { return Math.floor(номер / СТОЛБЦОВ); }
function столбецКлетки(номер) { return номер % СТОЛБЦОВ; }

/** Человеческое имя клетки: 0 → 'a1', 63 → 'h8'. */
function имяКлетки(номер) {
  return БУКВЫ[столбецКлетки(номер)] + (рядКлетки(номер) + 1);
}

/* Все 64 поля по порядку от a1 к h8 и обратный словарь «имя → номер».
   Словарь нужен, чтобы ход, пришедший снаружи со строками 'e2' и 'e4',
   превращался в номера одним взглядом, а не разбором букв. */
const ПОЛЯ = [];
const НОМЕР_ПОЛЯ = {};
for (let н = 0; н < КЛЕТОК; н++) {
  ПОЛЯ.push(имяКлетки(н));
  НОМЕР_ПОЛЯ[ПОЛЯ[н]] = н;
}

/** Номер клетки по имени. Мусор даёт минус единицу. */
function номерКлетки(имя) {
  if (typeof имя !== 'string') return -1;
  const номер = НОМЕР_ПОЛЯ[имя.toLowerCase()];
  return номер === undefined ? -1 : номер;
}

/* Цвет поля нужен только правилу о недостаточном материале: два слона
   на полях одного цвета мата не поставят. Поле a1 — тёмное. */
function тёмноеПоле(номер) {
  return (рядКлетки(номер) + столбецКлетки(номер)) % 2 === 0;
}

/* Углы и исходные поля королей — по ним живут права на рокировку. */
const A1 = 0, E1 = 4, H1 = 7;
const A8 = 56, E8 = 60, H8 = 63;

/* Восемь направлений. Первые четыре — прямые (ладья), последние четыре —
   диагонали (слон); ферзь ходит по всем восьми. */
const НАПРАВЛЕНИЯ = [
  { дряд: 1, дстолбец: 0 }, { дряд: -1, дстолбец: 0 },
  { дряд: 0, дстолбец: 1 }, { дряд: 0, дстолбец: -1 },
  { дряд: 1, дстолбец: 1 }, { дряд: 1, дстолбец: -1 },
  { дряд: -1, дстолбец: 1 }, { дряд: -1, дстолбец: -1 }
];
const ПРЯМЫХ_НАПРАВЛЕНИЙ = 4;

const ПРЫЖКИ_КОНЯ = [
  { дряд: 1, дстолбец: 2 }, { дряд: 2, дстолбец: 1 },
  { дряд: -1, дстолбец: 2 }, { дряд: -2, дстолбец: 1 },
  { дряд: 1, дстолбец: -2 }, { дряд: 2, дстолбец: -1 },
  { дряд: -1, дстолбец: -2 }, { дряд: -2, дстолбец: -1 }
];

/* Заранее посчитанные «куда можно смотреть с этого поля»:
     ЛУЧИ[поле][направление] — клетки по порядку до края доски,
     ХОДЫ_КОНЯ[поле], ХОДЫ_КОРОЛЯ[поле] — клетки, куда фигура прыгает.
   Считается один раз при загрузке. Без этого каждый поиск хода
   проверял бы границы доски заново, а поиск ходов — самое частое
   действие в игре: бот делает его миллионы раз. */
const ЛУЧИ = [];
const ХОДЫ_КОНЯ = [];
const ХОДЫ_КОРОЛЯ = [];

(function подготовитьТаблицы() {
  for (let поле = 0; поле < КЛЕТОК; поле++) {
    const ряд = рядКлетки(поле);
    const столбец = столбецКлетки(поле);
    const лучи = [];
    const король = [];
    for (const н of НАПРАВЛЕНИЯ) {
      const луч = [];
      for (let шаг = 1; ; шаг++) {
        const дальше = клетка(ряд + н.дряд * шаг, столбец + н.дстолбец * шаг);
        if (дальше === -1) break;
        луч.push(дальше);
      }
      лучи.push(луч);
      if (луч.length > 0) король.push(луч[0]);
    }
    const конь = [];
    for (const п of ПРЫЖКИ_КОНЯ) {
      const куда = клетка(ряд + п.дряд, столбец + п.дстолбец);
      if (куда !== -1) конь.push(куда);
    }
    ЛУЧИ.push(лучи);
    ХОДЫ_КОРОЛЯ.push(король);
    ХОДЫ_КОНЯ.push(конь);
  }
})();

/** Стоят ли два поля на одной прямой или диагонали. */
function наОднойЛинии(а, б) {
  const дряд = Math.abs(рядКлетки(а) - рядКлетки(б));
  const дстолбец = Math.abs(столбецКлетки(а) - столбецКлетки(б));
  return дряд === 0 || дстолбец === 0 || дряд === дстолбец;
}

/* =====================================================================
   ЧАСТЬ 2. ФИГУРЫ
   ===================================================================== */

/* Что лежит в клетке. Держим маленькими числами, а не объектами: доска
   из чисел копируется одним .slice(). Белые фигуры — 1..6, чёрные —
   те же плюс шесть. Снаружи чисел не видно: есть вопросы-функции
   «какого цвета» и «какого типа», а наружу выходят русские имена. */
const ПУСТО = 0;
const ПЕШКА = 1, КОНЬ = 2, СЛОН = 3, ЛАДЬЯ = 4, ФЕРЗЬ = 5, КОРОЛЬ = 6;
const СДВИГ_ЧЁРНЫХ = 6;

const БЕЛЫЕ = 'белые';
const ЧЁРНЫЕ = 'чёрные';

const ИМЕНА_ТИПОВ = [null, 'пешка', 'конь', 'слон', 'ладья', 'ферзь', 'король'];
const ТИП_ПО_ИМЕНИ = { 'пешка': ПЕШКА, 'конь': КОНЬ, 'слон': СЛОН, 'ладья': ЛАДЬЯ, 'ферзь': ФЕРЗЬ, 'король': КОРОЛЬ };
const ФИГУРЫ = ИМЕНА_ТИПОВ.slice(1);

/* Во что может превратиться пешка [1, ст. 3.7.5.1]: ферзь, ладья, слон
   или конь того же цвета — по выбору игрока, не обязательно в ферзя. */
const ПРЕВРАЩЕНИЯ = [ФЕРЗЬ, ЛАДЬЯ, СЛОН, КОНЬ];

/* Буквы для записи позиции (FEN) и для картинки доски: по номеру фигуры.
   Те же буквы идут в отпечаток позиции, по которому ловятся повторения. */
const БУКВЫ_FEN = '.PNBRQKpnbrqk';
const ФИГУРА_ПО_БУКВЕ = {};
for (let код = 1; код < БУКВЫ_FEN.length; код++) ФИГУРА_ПО_БУКВЕ[БУКВЫ_FEN[код]] = код;

/* Буквы фигур в записи хода — как в приложении C правил [1]: латинские,
   пешка без буквы. Так пишут во всём мире, и так просил штаб. */
const БУКВЫ_ЗАПИСИ = [null, '', 'N', 'B', 'R', 'Q', 'K'];
const ТИП_ПО_БУКВЕ_ЗАПИСИ = { N: КОНЬ, B: СЛОН, R: ЛАДЬЯ, Q: ФЕРЗЬ, K: КОРОЛЬ };

/** Цвет фигуры: 'белые', 'чёрные' или null для пустой клетки. */
function цветФигуры(фигура) {
  if (фигура === ПУСТО) return null;
  return фигура <= КОРОЛЬ ? БЕЛЫЕ : ЧЁРНЫЕ;
}

/** Тип фигуры без цвета: ПЕШКА … КОРОЛЬ. */
function типФигуры(фигура) {
  return фигура > КОРОЛЬ ? фигура - СДВИГ_ЧЁРНЫХ : фигура;
}

function фигураЦвета(тип, цвет) { return цвет === БЕЛЫЕ ? тип : тип + СДВИГ_ЧЁРНЫХ; }
function соперник(цвет) { return цвет === БЕЛЫЕ ? ЧЁРНЫЕ : БЕЛЫЕ; }

/* Куда для этого цвета «вперёд»: белые идут вверх (ряд растёт),
   чёрные — вниз. Нужно только пешкам. */
function вперёдДля(цвет) { return цвет === БЕЛЫЕ ? 1 : -1; }
function первыйРяд(цвет) { return цвет === БЕЛЫЕ ? 0 : РЯДОВ - 1; }
function исходныйРядПешек(цвет) { return цвет === БЕЛЫЕ ? 1 : РЯДОВ - 2; }
function рядПревращения(цвет) { return цвет === БЕЛЫЕ ? РЯДОВ - 1 : 0; }

/* Две стороны рокировки. Ключи прав в партии складываются из цвета и
   стороны: 'белыеКороткая', 'чёрныеДлинная' — чтобы права читались
   глазами прямо в JSON. */
const КОРОТКАЯ = 'короткая';
const ДЛИННАЯ = 'длинная';
function ключПрава(цвет, сторона) {
  return цвет + (сторона === КОРОТКАЯ ? 'Короткая' : 'Длинная');
}

/* =====================================================================
   ЧАСТЬ 3. СОСТОЯНИЕ ПАРТИИ

   Партия — обычные данные: списки, числа, строки и булевы. Никаких
   функций и ссылок на живые объекты. Поэтому её можно скопировать,
   сравнить целиком и отправить по сети как JSON.
   ===================================================================== */

/* Сколько раз должна повториться позиция, чтобы объявить ничью.
   По правилам [1, ст. 9.2] троекратное повторение — ничья по требованию
   игрока, пятикратное [ст. 9.6.1] — сама собой. В игре против бота
   требовать некому, поэтому объявляем ничью сразу на третьем разе —
   так же решено и в шашках. */
const ПОВТОРОВ_ДО_НИЧЬЕЙ = 3;

/* «Последние 50 ходов каждого игрока сделаны без движения пешек и без
   взятий» [1, ст. 9.3.2]. Ход в правилах — ход обеих сторон, поэтому
   внутри считаем полуходами: 50 ходов = 100 полуходов. Объявляем
   ничью сами по той же причине, что и повторение. */
const ПОЛУХОДОВ_БЕЗ_ВЗЯТИЙ_И_ПЕШЕК = 100;

/**
 * Заготовка партии из готовых частей. Отсюда стартуют и новая партия,
 * и позиция из FEN, и позиция из картинки.
 */
function собратьПартию(доска, ктоХодит, права, наПроходе, безВзятийИПешек, номерХода) {
  const партия = {
    доска: доска,                       // 64 клетки, числа-фигуры
    ходит: ктоХодит,                    // 'белые' или 'чёрные'
    рокировка: права,                   // { белыеКороткая, белыеДлинная, чёрныеКороткая, чёрныеДлинная }
    /* Поле, на которое можно взять на проходе (номер клетки), или -1.
       Держим только тогда, когда взятие реально возможно — иначе оно
       обмануло бы отпечаток позиции, см. отпечатокПозиции. */
    наПроходе: наПроходе,
    безВзятийИПешек: безВзятийИПешек,   // полуходов подряд для правила 50 ходов
    номерХода: номерХода,               // номер полного хода, как в записи партии
    полуходов: 0,                       // сколько ходов сделано в этой партии всего
    завершена: false,
    результат: null,                    // 'белые', 'чёрные' или 'ничья'
    причина: null,                      // почему кончилась — человеческими словами
    /* Позиции, которые уже были, — простым списком отпечатков. Держим
       внутри партии, иначе правило троекратного повторения пришлось бы
       пересказывать снаружи.

       Почему СПИСОК, а не словарь «отпечаток → сколько раз»: в шашках
       замер показал, что словарь с парой десятков ключей копируется
       в двести раз медленнее списка, а копировать партию бот будет на
       каждом шаге перебора. Список короткий: после хода пешкой или
       взятия старые позиции повториться уже не могут, и список
       начинается заново (см. применитьХод). */
    былиПозиции: []
  };
  if (партия.наПроходе !== -1 && !взятиеНаПроходеВозможно(партия)) партия.наПроходе = -1;
  запомнитьПозицию(партия);
  проверитьКонец(партия);
  return партия;
}

/** Все четыре права на рокировку сразу — как в начале партии. */
function всеПрава() {
  return { белыеКороткая: true, белыеДлинная: true, чёрныеКороткая: true, чёрныеДлинная: true };
}

/**
 * Новая партия: начальная расстановка [1, ст. 2.3], первый ход белых
 * [1, ст. 1.2].
 */
function создатьПартию() {
  const доска = new Array(КЛЕТОК).fill(ПУСТО);
  const порядок = [ЛАДЬЯ, КОНЬ, СЛОН, ФЕРЗЬ, КОРОЛЬ, СЛОН, КОНЬ, ЛАДЬЯ];
  for (let столбец = 0; столбец < СТОЛБЦОВ; столбец++) {
    доска[клетка(0, столбец)] = фигураЦвета(порядок[столбец], БЕЛЫЕ);
    доска[клетка(1, столбец)] = фигураЦвета(ПЕШКА, БЕЛЫЕ);
    доска[клетка(6, столбец)] = фигураЦвета(ПЕШКА, ЧЁРНЫЕ);
    доска[клетка(7, столбец)] = фигураЦвета(порядок[столбец], ЧЁРНЫЕ);
  }
  return собратьПартию(доска, БЕЛЫЕ, всеПрава(), -1, 0, 1);
}

/** Независимая копия партии: менять её можно как угодно, оригинал цел. */
function копияПартии(партия) {
  const копия = {
    доска: партия.доска.slice(),
    ходит: партия.ходит,
    рокировка: {
      белыеКороткая: партия.рокировка.белыеКороткая,
      белыеДлинная: партия.рокировка.белыеДлинная,
      чёрныеКороткая: партия.рокировка.чёрныеКороткая,
      чёрныеДлинная: партия.рокировка.чёрныеДлинная
    },
    наПроходе: партия.наПроходе,
    безВзятийИПешек: партия.безВзятийИПешек,
    номерХода: партия.номерХода,
    полуходов: партия.полуходов,
    завершена: партия.завершена,
    результат: партия.результат,
    причина: партия.причина,
    былиПозиции: партия.былиПозиции.slice()
  };
  /* Готовый список ходов — тот же самый, позиция ведь та же. Список
     никто не меняет (наружу уходит его копия), поэтому делить его
     между оригиналом и копией безопасно, а боту это экономит целый
     поиск ходов на каждом шаге. */
  if (партия.ходыНаготове) запомнитьХоды(копия, партия.ходыНаготове);
  return копия;
}

/* Список законных ходов позиции считается один раз и лежит при партии
   невидимым полем: JSON его не видит, сравнение партий — тоже, а
   «какие ходы возможны» отвечается мгновенно. Поле пересчитывается
   после каждого хода (в проверитьКонец) и само появляется у партии,
   восстановленной из JSON, — при первом же вопросе о ходах. */
function запомнитьХоды(партия, ходы) {
  Object.defineProperty(партия, 'ходыНаготове', {
    value: ходы, enumerable: false, writable: true, configurable: true
  });
}

function готовыеХоды(партия) {
  if (!партия.ходыНаготове) запомнитьХоды(партия, собратьХоды(партия));
  return партия.ходыНаготове;
}

/** Что стоит на поле: { цвет, тип } (тип — 'пешка', 'конь', …) или null. */
function фигура(партия, поле) {
  const номер = номерКлетки(поле);
  if (номер === -1) return null;
  const что = партия.доска[номер];
  if (что === ПУСТО) return null;
  return { цвет: цветФигуры(что), тип: ИМЕНА_ТИПОВ[типФигуры(что)] };
}

/** Чей сейчас ход. */
function чейХод(партия) {
  return партия.ходит;
}

/** Сколько у цвета фигур: { пешки, кони, слоны, ладьи, ферзи, короли, всего }. */
function сколькоФигур(партия, цвет) {
  const счёт = { пешки: 0, кони: 0, слоны: 0, ладьи: 0, ферзи: 0, короли: 0, всего: 0 };
  const поля = ['', 'пешки', 'кони', 'слоны', 'ладьи', 'ферзи', 'короли'];
  for (const что of партия.доска) {
    if (что === ПУСТО || цветФигуры(что) !== цвет) continue;
    счёт[поля[типФигуры(что)]]++;
    счёт.всего++;
  }
  return счёт;
}

/** Где стоит король цвета: номер клетки или -1, если его нет. */
function найтиКороля(доска, цвет) {
  const король = фигураЦвета(КОРОЛЬ, цвет);
  for (let н = 0; н < КЛЕТОК; н++) if (доска[н] === король) return н;
  return -1;
}

/** Поле короля цвета по-человечески: 'e1'. */
function полеКороля(партия, цвет) {
  const номер = найтиКороля(партия.доска, цвет);
  return номер === -1 ? null : ПОЛЯ[номер];
}

/** Права на рокировку строкой, как в FEN: 'KQkq', 'Kq' или '-'. */
function праваСтрокой(партия) {
  const п = партия.рокировка;
  const текст = (п.белыеКороткая ? 'K' : '') + (п.белыеДлинная ? 'Q' : '') +
                (п.чёрныеКороткая ? 'k' : '') + (п.чёрныеДлинная ? 'q' : '');
  return текст === '' ? '-' : текст;
}

/**
 * Отпечаток позиции — строка, по которой позиции сравниваются.
 * «Позиции одинаковы, если ход того же игрока, фигуры тех же видов и
 * цветов стоят на тех же полях, и возможные ходы всех фигур те же»
 * [1, ст. 9.2.2]. Поэтому в отпечаток входят не только фигуры и очередь
 * хода, но и права на рокировку и возможность взятия на проходе —
 * без них две одинаковые с виду доски оказались бы разными позициями,
 * а мы сочли бы их одной.
 */
function отпечатокПозиции(партия) {
  let слепок = '';
  for (let н = 0; н < КЛЕТОК; н++) слепок += БУКВЫ_FEN[партия.доска[н]];
  return слепок + ' ' + (партия.ходит === БЕЛЫЕ ? 'w' : 'b') + ' ' + праваСтрокой(партия) +
         ' ' + (партия.наПроходе === -1 ? '-' : ПОЛЯ[партия.наПроходе]);
}

/* =====================================================================
   ЧАСТЬ 4. НАПАДЕНИЕ НА ПОЛЕ

   Один вопрос, на который опирается половина правил: «бьёт ли этот
   цвет это поле». Им проверяются шах, рокировка и законность хода.
   ===================================================================== */

/** Нападает ли цвет на поле. Смотрим от поля в стороны: кто его видит. */
function подБоем(доска, поле, цвет) {
  const конь = фигураЦвета(КОНЬ, цвет);
  for (const откуда of ХОДЫ_КОНЯ[поле]) if (доска[откуда] === конь) return true;

  const король = фигураЦвета(КОРОЛЬ, цвет);
  for (const откуда of ХОДЫ_КОРОЛЯ[поле]) if (доска[откуда] === король) return true;

  /* Пешка бьёт наискосок вперёд, значит, нападающая пешка стоит на
     ряд «позади» поля с точки зрения своего цвета. */
  const пешка = фигураЦвета(ПЕШКА, цвет);
  const рядПешки = рядКлетки(поле) - вперёдДля(цвет);
  const столбец = столбецКлетки(поле);
  const слева = клетка(рядПешки, столбец - 1);
  const справа = клетка(рядПешки, столбец + 1);
  if (слева !== -1 && доска[слева] === пешка) return true;
  if (справа !== -1 && доска[справа] === пешка) return true;

  /* Дальнобойные: идём по лучу до первой фигуры. Своя или не та —
     луч перекрыт, дальше смотреть незачем. */
  const ферзь = фигураЦвета(ФЕРЗЬ, цвет);
  const ладья = фигураЦвета(ЛАДЬЯ, цвет);
  const слон = фигураЦвета(СЛОН, цвет);
  const лучи = ЛУЧИ[поле];
  for (let н = 0; н < лучи.length; н++) {
    const дальнобойная = н < ПРЯМЫХ_НАПРАВЛЕНИЙ ? ладья : слон;
    const луч = лучи[н];
    for (let i = 0; i < луч.length; i++) {
      const что = доска[луч[i]];
      if (что === ПУСТО) continue;
      if (что === дальнобойная || что === ферзь) return true;
      break;
    }
  }
  return false;
}

/** Под шахом ли король того, чей ход [1, ст. 3.9.1]. */
function подШахом(партия) {
  const король = найтиКороля(партия.доска, партия.ходит);
  return король !== -1 && подБоем(партия.доска, король, соперник(партия.ходит));
}

/* =====================================================================
   ЧАСТЬ 5. КАКИЕ ХОДЫ ВОЗМОЖНЫ

   Ход — обычные данные:
     { откуда, куда, фигура, взятие, превращение, рокировка, наПроходе }
   где «фигура» и «взятие» — русские имена ('конь', 'пешка' или null,
   если взятия нет), «превращение» — во что стала пешка или null,
   «рокировка» — 'короткая', 'длинная' или null, «наПроходе» — true
   только для взятия на проходе.

   Сначала собираем все ходы «по геометрии» (как фигура двигается),
   потом отсеиваем те, что оставляют своего короля под шахом
   [1, ст. 3.9.2]. Остаются законные.
   ===================================================================== */

function создатьХод(от, до, тип, взятие, превращение, рокировка, наПроходе) {
  return {
    откуда: ПОЛЯ[от],
    куда: ПОЛЯ[до],
    фигура: ИМЕНА_ТИПОВ[тип],
    взятие: взятие === ПУСТО ? null : ИМЕНА_ТИПОВ[взятие],
    превращение: превращение === ПУСТО ? null : ИМЕНА_ТИПОВ[превращение],
    рокировка: рокировка,
    наПроходе: наПроходе
  };
}

/**
 * Ходы пешки [1, ст. 3.7]: шаг вперёд на пустое поле; с исходной
 * горизонтали — на два поля, если оба пусты; бьёт наискосок вперёд;
 * бьёт на проходе; дойдя до последней горизонтали — превращается.
 */
function ходыПешки(партия, от, цвет, ходы) {
  const доска = партия.доска;
  const вперёд = вперёдДля(цвет);
  const ряд = рядКлетки(от);
  const столбец = столбецКлетки(от);
  const шаг = клетка(ряд + вперёд, столбец);
  if (шаг === -1) return;
  const превращается = рядКлетки(шаг) === рядПревращения(цвет);

  if (доска[шаг] === ПУСТО) {
    добавитьХодПешки(ходы, от, шаг, ПУСТО, превращается);
    if (ряд === исходныйРядПешек(цвет)) {
      const два = клетка(ряд + 2 * вперёд, столбец);
      if (доска[два] === ПУСТО) ходы.push(создатьХод(от, два, ПЕШКА, ПУСТО, ПУСТО, null, false));
    }
  }
  for (let сторона = -1; сторона <= 1; сторона += 2) {
    const цель = клетка(ряд + вперёд, столбец + сторона);
    if (цель === -1) continue;
    const что = доска[цель];
    if (что !== ПУСТО) {
      if (цветФигуры(что) !== цвет) добавитьХодПешки(ходы, от, цель, типФигуры(что), превращается);
    } else if (цель === партия.наПроходе) {
      /* Взятие на проходе [1, ст. 3.7.4.1]: поле прихода пусто, а битая
         пешка стоит рядом. Само поле «наПроходе» живёт в партии ровно
         один ход — его ставит применитьХод и он же снимает. */
      ходы.push(создатьХод(от, цель, ПЕШКА, ПЕШКА, ПУСТО, null, true));
    }
  }
}

/* Пешка на последней горизонтали обязана превратиться, и выбор фигуры —
   часть хода [1, ст. 3.7.5.1]. Поэтому одно превращение — это четыре
   разных хода в списке: игроку есть из чего выбрать. */
function добавитьХодПешки(ходы, от, до, взятие, превращается) {
  if (!превращается) {
    ходы.push(создатьХод(от, до, ПЕШКА, взятие, ПУСТО, null, false));
    return;
  }
  for (const тип of ПРЕВРАЩЕНИЯ) ходы.push(создатьХод(от, до, ПЕШКА, взятие, тип, null, false));
}

/** Ходы прыгающих фигур — коня и короля: на любое из своих полей, если там не своя фигура. */
function ходыПрыжком(доска, от, цвет, куда, тип, ходы) {
  for (const до of куда) {
    const что = доска[до];
    if (что === ПУСТО) ходы.push(создатьХод(от, до, тип, ПУСТО, ПУСТО, null, false));
    else if (цветФигуры(что) !== цвет) ходы.push(создатьХод(от, до, тип, типФигуры(что), ПУСТО, null, false));
  }
}

/** Ходы дальнобойных — слона, ладьи, ферзя: по лучам до первой фигуры. */
function ходыПоЛучам(доска, от, цвет, первыйЛуч, последнийЛуч, тип, ходы) {
  const лучи = ЛУЧИ[от];
  for (let н = первыйЛуч; н < последнийЛуч; н++) {
    const луч = лучи[н];
    for (let i = 0; i < луч.length; i++) {
      const до = луч[i];
      const что = доска[до];
      if (что === ПУСТО) { ходы.push(создатьХод(от, до, тип, ПУСТО, ПУСТО, null, false)); continue; }
      if (цветФигуры(что) !== цвет) ходы.push(создатьХод(от, до, тип, типФигуры(что), ПУСТО, null, false));
      break;
    }
  }
}

/**
 * Рокировка [1, ст. 3.8.2]. Все условия сразу:
 *   - право не потеряно: король и эта ладья ещё не ходили [3.8.2.1];
 *   - между королём и ладьёй пусто [3.8.2.2];
 *   - король не под шахом, не проходит через битое поле и не встаёт
 *     на битое [3.8.2.2].
 * Ладья при этом МОЖЕТ быть под боем, а при длинной рокировке поле b
 * может быть битым — король через него не проходит. На этом чаще всего
 * ошибаются, поэтому оба случая выписаны в самопроверке.
 */
function ходыРокировки(партия, король, шах, ходы) {
  if (шах || король === -1) return;
  const цвет = партия.ходит;
  const ряд = первыйРяд(цвет);
  if (король !== клетка(ряд, 4)) return;
  const доска = партия.доска;
  const враг = соперник(цвет);
  const ладья = фигураЦвета(ЛАДЬЯ, цвет);
  const поле = function (столбец) { return клетка(ряд, столбец); };

  if (партия.рокировка[ключПрава(цвет, КОРОТКАЯ)] && доска[поле(7)] === ладья &&
      доска[поле(5)] === ПУСТО && доска[поле(6)] === ПУСТО &&
      !подБоем(доска, поле(5), враг) && !подБоем(доска, поле(6), враг)) {
    ходы.push(создатьХод(король, поле(6), КОРОЛЬ, ПУСТО, ПУСТО, КОРОТКАЯ, false));
  }
  if (партия.рокировка[ключПрава(цвет, ДЛИННАЯ)] && доска[поле(0)] === ладья &&
      доска[поле(1)] === ПУСТО && доска[поле(2)] === ПУСТО && доска[поле(3)] === ПУСТО &&
      !подБоем(доска, поле(3), враг) && !подБоем(доска, поле(2), враг)) {
    ходы.push(создатьХод(король, поле(2), КОРОЛЬ, ПУСТО, ПУСТО, ДЛИННАЯ, false));
  }
}

/**
 * Переставить фигуры на доске по ходу — без счётчиков и очереди хода.
 * Общая часть настоящего хода и пробного (когда проверяем, не остался
 * ли король под шахом): одна и та же функция, чтобы проба и правда
 * никогда не разошлись.
 */
function переставить(доска, ход, от, до) {
  const что = доска[от];
  доска[от] = ПУСТО;
  /* При взятии на проходе битая пешка стоит не на поле прихода,
     а рядом с ним — на ряду бьющей пешки. */
  if (ход.наПроходе) доска[клетка(рядКлетки(от), столбецКлетки(до))] = ПУСТО;
  if (ход.рокировка) {
    const ряд = рядКлетки(от);
    const короткая = ход.рокировка === КОРОТКАЯ;
    const ладьяОт = клетка(ряд, короткая ? 7 : 0);
    const ладьяДо = клетка(ряд, короткая ? 5 : 3);
    доска[ладьяДо] = доска[ладьяОт];
    доска[ладьяОт] = ПУСТО;
  }
  доска[до] = ход.превращение
    ? фигураЦвета(ТИП_ПО_ИМЕНИ[ход.превращение], цветФигуры(что))
    : что;
}

/**
 * Оставляет ли ход своего короля под шахом [1, ст. 3.9.2]. Проверяем
 * на пробной копии доски: сделали ход — посмотрели, бьют ли короля.
 *
 * Пробу делаем не для каждого хода. Если король не под шахом, то
 * подставить его может только связанная фигура, а связанная фигура
 * всегда стоит с королём на одной линии. Значит, фигуре не на линии
 * с королём проба не нужна — это большинство ходов, и без такого
 * отсева поиск ходов был бы в несколько раз медленнее. Всегда
 * проверяем: ходы самого короля, любые ходы под шахом и взятие на
 * проходе — оно снимает с доски сразу две пешки, и линия к королю
 * может открыться там, где никто не стоял.
 */
function оставляетКороляПодШахом(партия, ход, король, шах) {
  const от = НОМЕР_ПОЛЯ[ход.откуда];
  const до = НОМЕР_ПОЛЯ[ход.куда];
  const ходитКороль = от === король;
  if (!шах && !ходитКороль && !ход.наПроходе && !наОднойЛинии(от, король)) return false;
  const проба = партия.доска.slice();
  переставить(проба, ход, от, до);
  return подБоем(проба, ходитКороль ? до : король, соперник(партия.ходит));
}

/** Все законные ходы того, чей ход. */
function собратьХоды(партия) {
  const доска = партия.доска;
  const цвет = партия.ходит;
  const король = найтиКороля(доска, цвет);
  const шах = король !== -1 && подБоем(доска, король, соперник(цвет));
  const кандидаты = [];
  for (let от = 0; от < КЛЕТОК; от++) {
    const что = доска[от];
    if (что === ПУСТО || цветФигуры(что) !== цвет) continue;
    switch (типФигуры(что)) {
      case ПЕШКА: ходыПешки(партия, от, цвет, кандидаты); break;
      case КОНЬ: ходыПрыжком(доска, от, цвет, ХОДЫ_КОНЯ[от], КОНЬ, кандидаты); break;
      case СЛОН: ходыПоЛучам(доска, от, цвет, ПРЯМЫХ_НАПРАВЛЕНИЙ, НАПРАВЛЕНИЯ.length, СЛОН, кандидаты); break;
      case ЛАДЬЯ: ходыПоЛучам(доска, от, цвет, 0, ПРЯМЫХ_НАПРАВЛЕНИЙ, ЛАДЬЯ, кандидаты); break;
      case ФЕРЗЬ: ходыПоЛучам(доска, от, цвет, 0, НАПРАВЛЕНИЯ.length, ФЕРЗЬ, кандидаты); break;
      case КОРОЛЬ: ходыПрыжком(доска, от, цвет, ХОДЫ_КОРОЛЯ[от], КОРОЛЬ, кандидаты); break;
    }
  }
  ходыРокировки(партия, король, шах, кандидаты);

  const законные = [];
  for (const ход of кандидаты) {
    if (!оставляетКороляПодШахом(партия, ход, король, шах)) законные.push(ход);
  }
  return законные;
}

/* Есть ли законное взятие на проходе. Нужно, чтобы держать поле
   «наПроходе» в партии, только когда взятие возможно: по [1, ст. 9.2.2]
   позиция с возможным взятием на проходе — другая позиция, а с
   невозможным — та же самая. */
function взятиеНаПроходеВозможно(партия) {
  const цель = партия.наПроходе;
  if (цель === -1) return false;
  const доска = партия.доска;
  const цвет = партия.ходит;
  const король = найтиКороля(доска, цвет);
  const шах = король !== -1 && подБоем(доска, король, соперник(цвет));
  const пешка = фигураЦвета(ПЕШКА, цвет);
  const ряд = рядКлетки(цель) - вперёдДля(цвет);
  for (let сторона = -1; сторона <= 1; сторона += 2) {
    const от = клетка(ряд, столбецКлетки(цель) + сторона);
    if (от === -1 || доска[от] !== пешка) continue;
    const ход = создатьХод(от, цель, ПЕШКА, ПЕШКА, ПУСТО, null, true);
    if (!оставляетКороляПодШахом(партия, ход, король, шах)) return true;
  }
  return false;
}

/**
 * Все законные ходы. У завершённой партии ходов нет.
 *
 * Список отдаётся каждый раз новый — его можно сортировать и резать.
 * А вот сами ходы в нём — те же объекты, что партия держит наготове,
 * и менять их снаружи нельзя: испортится и её список. Нужен ход с
 * другой начинкой — соберите свой объект { откуда, куда, превращение },
 * сделатьХод такой примет.
 */
function возможныеХоды(партия) {
  if (партия.завершена) return [];
  return готовыеХоды(партия).slice();
}

/** Законные ходы фигуры, стоящей на поле. Чужая фигура или пустое поле — пусто. */
function ходыФигуры(партия, поле) {
  const имя = typeof поле === 'string' ? поле.toLowerCase() : '';
  return возможныеХоды(партия).filter(function (ход) { return ход.откуда === имя; });
}

/* =====================================================================
   ЧАСТЬ 6. СДЕЛАТЬ ХОД
   ===================================================================== */

/**
 * Найти среди законных ходов тот, что просят снаружи. Достаточно
 * назвать «откуда» и «куда»; для превращения — ещё и фигуру, иначе ход
 * неоднозначен и не делается: выбор фигуры по правилам за игроком,
 * а не за нами. Строку принимаем как запись хода ('Nf3', 'e8=Q', 'O-O').
 */
function найтиХод(партия, ход) {
  if (typeof ход === 'string') return ходИзЗаписи(партия, ход);
  if (!ход || typeof ход !== 'object') return null;
  const откуда = String(ход.откуда).toLowerCase();
  const куда = String(ход.куда).toLowerCase();
  let годные = готовыеХоды(партия).filter(function (х) {
    return х.откуда === откуда && х.куда === куда;
  });
  if (ход.превращение) {
    годные = годные.filter(function (х) { return х.превращение === ход.превращение; });
  }
  return годные.length === 1 ? годные[0] : null;
}

/* Право на рокировку теряется навсегда, как только король или ладья
   сошли с места [1, ст. 3.8.2.1]. Ладью не обязательно двигать самому:
   если её взяли на исходном поле, право с этой стороны тоже пропадает —
   рокировать больше не с чем. Поэтому смотрим и на «откуда», и на «куда». */
function обновитьПраваРокировки(права, цвет, от, до, тип) {
  if (тип === КОРОЛЬ) {
    права[ключПрава(цвет, КОРОТКАЯ)] = false;
    права[ключПрава(цвет, ДЛИННАЯ)] = false;
  }
  снятьПравоУгла(права, от);
  снятьПравоУгла(права, до);
}

function снятьПравоУгла(права, поле) {
  if (поле === A1) права.белыеДлинная = false;
  else if (поле === H1) права.белыеКороткая = false;
  else if (поле === A8) права.чёрныеДлинная = false;
  else if (поле === H8) права.чёрныеКороткая = false;
}

/** Применить уже найденный законный ход: доска, права, счётчики, очередь. */
function применитьХод(партия, ход) {
  const цвет = партия.ходит;
  const от = НОМЕР_ПОЛЯ[ход.откуда];
  const до = НОМЕР_ПОЛЯ[ход.куда];
  const тип = типФигуры(партия.доска[от]);

  переставить(партия.доска, ход, от, до);
  обновитьПраваРокировки(партия.рокировка, цвет, от, до, тип);

  /* Поле для взятия на проходе появляется только после хода пешки на
     два поля и живёт ровно один ход [1, ст. 3.7.4.1]. Поле — то, через
     которое пешка перепрыгнула, то есть посередине между «откуда» и «куда». */
  партия.наПроходе = тип === ПЕШКА && Math.abs(до - от) === 2 * СТОЛБЦОВ ? (от + до) / 2 : -1;

  /* Ход пешкой и взятие необратимы: после них прежние позиции
     повториться не могут, и счётчик 50 ходов начинается заново
     [1, ст. 9.3.2]. */
  const необратимый = тип === ПЕШКА || ход.взятие !== null;
  партия.безВзятийИПешек = необратимый ? 0 : партия.безВзятийИПешек + 1;

  партия.ходит = соперник(цвет);
  партия.полуходов++;
  if (цвет === ЧЁРНЫЕ) партия.номерХода++;

  if (партия.наПроходе !== -1 && !взятиеНаПроходеВозможно(партия)) партия.наПроходе = -1;
  if (необратимый) партия.былиПозиции = [];
  запомнитьПозицию(партия);
  проверитьКонец(партия);
}

/**
 * Сделать ход. Меняет партию на месте и отвечает: получилось или нет.
 * Незаконный ход не меняет ничего — это важно и экрану (тык мимо),
 * и проверкам (попытка нарушить правила должна быть отбита, а не
 * наполовину выполнена). Ход можно дать объектом { откуда, куда,
 * превращение? } или строкой записи ('Nf3', 'exd5', 'O-O', 'e8=Q').
 */
function сделатьХод(партия, ход) {
  if (партия.завершена) return false;
  const выбранный = найтиХод(партия, ход);
  if (!выбранный) return false;
  применитьХод(партия, выбранный);
  return true;
}

/* =====================================================================
   ЧАСТЬ 7. КОНЕЦ ПАРТИИ И НИЧЬИ
   ===================================================================== */

function запомнитьПозицию(партия) {
  партия.былиПозиции.push(отпечатокПозиции(партия));
}

/** Сколько раз уже встречалась нынешняя позиция (считая её саму). */
function встреченоРаз(партия) {
  const отпечаток = отпечатокПозиции(партия);
  let сколько = 0;
  for (let i = 0; i < партия.былиПозиции.length; i++) {
    if (партия.былиПозиции[i] === отпечаток) сколько++;
  }
  return сколько;
}

/**
 * Мёртвая позиция [1, ст. 5.2.2]: ни одна сторона не может поставить
 * мат никакой последовательностью ходов. Берём общепринятый набор:
 * король против короля; король и слон или конь против короля;
 * только слоны с обеих сторон, и все на полях одного цвета.
 * Два коня против голого короля мёртвой позицией не считаются:
 * мат там возможен, пусть и только с помощью соперника.
 */
function недостаточноМатериала(партия) {
  let кони = 0;
  let слоновНаТёмных = 0;
  let слоновНаСветлых = 0;
  for (let н = 0; н < КЛЕТОК; н++) {
    const что = партия.доска[н];
    if (что === ПУСТО) continue;
    const тип = типФигуры(что);
    if (тип === ПЕШКА || тип === ЛАДЬЯ || тип === ФЕРЗЬ) return false;
    if (тип === КОНЬ) кони++;
    if (тип === СЛОН) { if (тёмноеПоле(н)) слоновНаТёмных++; else слоновНаСветлых++; }
  }
  if (кони === 0) return слоновНаТёмных === 0 || слоновНаСветлых === 0;
  return кони === 1 && слоновНаТёмных + слоновНаСветлых === 0;
}

function записатьИтог(партия, результат, причина) {
  партия.завершена = true;
  партия.результат = результат;
  партия.причина = причина;
}

/* Падежи цвета — чтобы причина читалась по-русски. */
function кому(цвет) { return цвет === БЕЛЫЕ ? 'белым' : 'чёрным'; }

/**
 * Кончилась ли партия — проверяется после каждого хода.
 *
 * Сначала смотрим, есть ли ходы: нет и шах — мат [1, ст. 5.1.1],
 * нет и шаха нет — пат [1, ст. 5.2.1]. Мат идёт первым нарочно:
 * если матующий ход одновременно сотый без взятий, побеждает мат
 * [1, ст. 9.6.2]. Потом ничьи: мёртвая позиция, троекратное
 * повторение, 50 ходов.
 */
function проверитьКонец(партия) {
  const ходы = собратьХоды(партия);
  запомнитьХоды(партия, ходы);
  if (партия.завершена) return;
  if (ходы.length === 0) {
    if (подШахом(партия)) {
      записатьИтог(партия, соперник(партия.ходит), 'мат: ' + кому(партия.ходит) + ' некуда деться');
    } else {
      записатьИтог(партия, 'ничья', 'пат: ' + кому(партия.ходит) + ' нечем ходить, а шаха нет');
    }
    return;
  }
  if (недостаточноМатериала(партия)) {
    записатьИтог(партия, 'ничья', 'мата поставить нечем: на доске недостаточно фигур');
    return;
  }
  if (встреченоРаз(партия) >= ПОВТОРОВ_ДО_НИЧЬЕЙ) {
    записатьИтог(партия, 'ничья', 'одна и та же позиция повторилась три раза');
    return;
  }
  if (партия.безВзятийИПешек >= ПОЛУХОДОВ_БЕЗ_ВЗЯТИЙ_И_ПЕШЕК) {
    записатьИтог(партия, 'ничья', 'пятьдесят ходов подряд без взятий и без ходов пешками');
  }
}

/** Кончилась ли партия. */
function партияЗавершена(партия) {
  return партия.завершена;
}

/**
 * Итог партии или null, если она ещё идёт:
 *   { победитель: 'белые' | 'чёрные' | null, ничья: true|false, причина: '…' }
 */
function итог(партия) {
  if (!партия.завершена) return null;
  const ничья = партия.результат === 'ничья';
  return {
    победитель: ничья ? null : партия.результат,
    ничья: ничья,
    причина: партия.причина
  };
}

/* =====================================================================
   ЧАСТЬ 8. ЗАПИСЬ ХОДА

   Стандартная алгебраическая запись [1, приложение C]: Nf3, exd5, O-O,
   e8=Q+, Qxf7#. Буквы фигур латинские, как принято во всём мире.
   ===================================================================== */

/* Если две одинаковые фигуры могут пойти на одно поле, к букве фигуры
   добавляют вертикаль исходного поля; если и вертикали совпадают —
   горизонталь; если совпадает и то и другое (три ферзя) — поле целиком
   [1, приложение C.10]. */
function уточнение(партия, ход) {
  const такиеЖе = готовыеХоды(партия).filter(function (х) {
    return х.фигура === ход.фигура && х.куда === ход.куда && х.откуда !== ход.откуда;
  });
  if (такиеЖе.length === 0) return '';
  const вертикаль = ход.откуда[0];
  const горизонталь = ход.откуда[1];
  const таЖеВертикаль = такиеЖе.some(function (х) { return х.откуда[0] === вертикаль; });
  const таЖеГоризонталь = такиеЖе.some(function (х) { return х.откуда[1] === горизонталь; });
  if (!таЖеВертикаль) return вертикаль;
  if (!таЖеГоризонталь) return горизонталь;
  return ход.откуда;
}

/**
 * Запись хода в позиции. Партия нужна та, в которой ход ещё не сделан:
 * без неё не понять, надо ли уточнять фигуру и ставить ли «+» или «#».
 */
function запись(партия, ход) {
  let текст;
  if (ход.рокировка) {
    текст = ход.рокировка === КОРОТКАЯ ? 'O-O' : 'O-O-O';
  } else if (ход.фигура === 'пешка') {
    текст = (ход.взятие ? ход.откуда[0] + 'x' : '') + ход.куда +
            (ход.превращение ? '=' + БУКВЫ_ЗАПИСИ[ТИП_ПО_ИМЕНИ[ход.превращение]] : '');
  } else {
    текст = БУКВЫ_ЗАПИСИ[ТИП_ПО_ИМЕНИ[ход.фигура]] + уточнение(партия, ход) +
            (ход.взятие ? 'x' : '') + ход.куда;
  }
  /* Шах и мат узнаём, сделав ход на копии: пересказывать здесь правила
     шаха — значит однажды разойтись с ними. */
  const копия = копияПартии(партия);
  if (сделатьХод(копия, ход) && подШахом(копия)) {
    текст += копия.завершена && копия.результат !== 'ничья' ? '#' : '+';
  }
  return текст;
}

/* Запись без украшений: без «+», «#», «!?», без «x» и «=», нули вместо
   букв «O» тоже прощаем. Так сравнение записей не зависит от вкуса
   того, кто её напечатал. */
function упроститьЗапись(текст) {
  return String(текст).replace(/e\.p\./gi, '').replace(/[+#!?x=:\s]/g, '').replace(/0/g, 'O');
}

/**
 * Ход по записи: 'Nf3', 'exd5', 'O-O', 'e8=Q', а также длинной формой
 * 'e2e4' или 'e7e8q'. Возвращает ход из списка законных или null.
 */
function ходИзЗаписи(партия, текст) {
  const чистый = упроститьЗапись(текст);
  const ходы = готовыеХоды(партия);
  const длинная = /^([a-h][1-8])-?([a-h][1-8])([qrbn])?$/i.exec(чистый);
  if (длинная) {
    const откуда = длинная[1].toLowerCase();
    const куда = длинная[2].toLowerCase();
    const превращение = длинная[3] ? ИМЕНА_ТИПОВ[ТИП_ПО_БУКВЕ_ЗАПИСИ[длинная[3].toUpperCase()]] : null;
    const годные = ходы.filter(function (х) {
      return х.откуда === откуда && х.куда === куда && (превращение === null ? true : х.превращение === превращение);
    });
    return годные.length === 1 ? годные[0] : null;
  }
  for (const ход of ходы) {
    if (упроститьЗапись(запись(партия, ход)) === чистый) return ход;
  }
  return null;
}

/* =====================================================================
   ЧАСТЬ 9. ПОЗИЦИЯ СЛОВАМИ: FEN И КАРТИНКА

   FEN — общепринятая строка позиции; в ней записаны все эталонные
   позиции с chessprogramming.org, поэтому без неё сверку не сделать.
   Картинка — восемь строк по восемь знаков — для позиций-ловушек:
   правило проще нарисовать, чем описать.
   ===================================================================== */

/* Проверка расстановки перед сборкой партии. Кривая позиция — это
   ошибка с понятным текстом, а не тихо испорченная доска. */
function проверитьРасстановку(доска, ктоХодит) {
  for (const цвет of [БЕЛЫЕ, ЧЁРНЫЕ]) {
    let королей = 0;
    for (const что of доска) if (что === фигураЦвета(КОРОЛЬ, цвет)) королей++;
    if (королей !== 1) throw new Error('У ' + (цвет === БЕЛЫЕ ? 'белых' : 'чёрных') + ' должен быть ровно один король, а найдено ' + королей);
  }
  for (let столбец = 0; столбец < СТОЛБЦОВ; столбец++) {
    for (const ряд of [0, РЯДОВ - 1]) {
      const что = доска[клетка(ряд, столбец)];
      if (что !== ПУСТО && типФигуры(что) === ПЕШКА) {
        throw new Error('Пешка на поле ' + ПОЛЯ[клетка(ряд, столбец)] + ': на крайней горизонтали пешек не бывает');
      }
    }
  }
  const чужойКороль = найтиКороля(доска, соперник(ктоХодит));
  if (подБоем(доска, чужойКороль, ктоХодит)) {
    throw new Error('Король ' + (ктоХодит === БЕЛЫЕ ? 'чёрных' : 'белых') + ' под шахом, хотя ход не его — так не бывает');
  }
}

/* Право на рокировку возможно, только если король и ладья стоят на
   исходных полях. Иначе право в FEN — описка. */
function проверитьПрава(доска, права) {
  const проверки = [
    ['белыеКороткая', E1, H1, БЕЛЫЕ], ['белыеДлинная', E1, A1, БЕЛЫЕ],
    ['чёрныеКороткая', E8, H8, ЧЁРНЫЕ], ['чёрныеДлинная', E8, A8, ЧЁРНЫЕ]
  ];
  for (const [ключ, король, ладья, цвет] of проверки) {
    if (!права[ключ]) continue;
    if (доска[король] !== фигураЦвета(КОРОЛЬ, цвет) || доска[ладья] !== фигураЦвета(ЛАДЬЯ, цвет)) {
      throw new Error('Право на рокировку «' + ключ + '» невозможно: король или ладья не на исходном поле');
    }
  }
}

/**
 * Партия из строки FEN, например начальная:
 *   'rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1'
 * Части: расстановка (с восьмой горизонтали), чей ход, права на
 * рокировку, поле взятия на проходе, полуходов без взятий и пешек,
 * номер хода. Последние четыре части можно опустить.
 */
function партияИзFEN(текст) {
  const части = String(текст).trim().split(/\s+/);
  if (части.length < 2) throw new Error('В FEN нужны хотя бы расстановка и чей ход: «' + текст + '»');

  const ряды = части[0].split('/');
  if (ряды.length !== РЯДОВ) throw new Error('В расстановке должно быть 8 горизонталей, а пришло ' + ряды.length);
  const доска = new Array(КЛЕТОК).fill(ПУСТО);
  for (let i = 0; i < РЯДОВ; i++) {
    const ряд = РЯДОВ - 1 - i;
    let столбец = 0;
    for (const знак of ряды[i]) {
      if (знак >= '1' && знак <= '8') { столбец += Number(знак); continue; }
      const код = ФИГУРА_ПО_БУКВЕ[знак];
      if (код === undefined) throw new Error('Непонятный знак «' + знак + '» в FEN');
      if (столбец >= СТОЛБЦОВ) throw new Error('В горизонтали «' + ряды[i] + '» больше 8 полей');
      доска[клетка(ряд, столбец)] = код;
      столбец++;
    }
    if (столбец !== СТОЛБЦОВ) throw new Error('В горизонтали «' + ряды[i] + '» не 8 полей');
  }

  if (части[1] !== 'w' && части[1] !== 'b') throw new Error('Чей ход должен быть «w» или «b», а пришло «' + части[1] + '»');
  const ходит = части[1] === 'w' ? БЕЛЫЕ : ЧЁРНЫЕ;

  const праваТекст = части[2] || '-';
  const права = {
    белыеКороткая: праваТекст.indexOf('K') !== -1,
    белыеДлинная: праваТекст.indexOf('Q') !== -1,
    чёрныеКороткая: праваТекст.indexOf('k') !== -1,
    чёрныеДлинная: праваТекст.indexOf('q') !== -1
  };

  let наПроходе = -1;
  if (части[3] && части[3] !== '-') {
    наПроходе = номерКлетки(части[3]);
    const нужныйРяд = ходит === БЕЛЫЕ ? 5 : 2;
    const битаяПешка = наПроходе === -1 ? -1 : клетка(рядКлетки(наПроходе) - вперёдДля(ходит), столбецКлетки(наПроходе));
    if (наПроходе === -1 || рядКлетки(наПроходе) !== нужныйРяд || доска[наПроходе] !== ПУСТО ||
        доска[битаяПешка] !== фигураЦвета(ПЕШКА, соперник(ходит))) {
      throw new Error('Поле взятия на проходе «' + части[3] + '» не сходится с расстановкой');
    }
  }

  const безВзятий = части[4] === undefined ? 0 : Number(части[4]);
  const номерХода = части[5] === undefined ? 1 : Number(части[5]);
  if (!(безВзятий >= 0) || !(номерХода >= 1)) throw new Error('Счётчики в FEN должны быть числами: «' + текст + '»');

  проверитьРасстановку(доска, ходит);
  проверитьПрава(доска, права);
  return собратьПартию(доска, ходит, права, наПроходе, безВзятий, номерХода);
}

/** Позиция строкой FEN — шесть частей, как принято. */
function fenПартии(партия) {
  let текст = '';
  for (let ряд = РЯДОВ - 1; ряд >= 0; ряд--) {
    let пустых = 0;
    for (let столбец = 0; столбец < СТОЛБЦОВ; столбец++) {
      const что = партия.доска[клетка(ряд, столбец)];
      if (что === ПУСТО) { пустых++; continue; }
      if (пустых > 0) { текст += пустых; пустых = 0; }
      текст += БУКВЫ_FEN[что];
    }
    if (пустых > 0) текст += пустых;
    if (ряд > 0) текст += '/';
  }
  return текст + ' ' + (партия.ходит === БЕЛЫЕ ? 'w' : 'b') + ' ' + праваСтрокой(партия) + ' ' +
         (партия.наПроходе === -1 ? '-' : ПОЛЯ[партия.наПроходе]) + ' ' +
         партия.безВзятийИПешек + ' ' + партия.номерХода;
}

/**
 * Партия из картинки — восьми строк по восемь знаков, верхняя строка —
 * восьмая горизонталь, как человек видит доску со стороны белых.
 * Белые фигуры заглавными (K Q R B N P), чёрные строчными, '.' или
 * пробел — пусто. Права на рокировку считаются по расстановке: есть,
 * если король и ладья стоят на исходных полях. Взятия на проходе нет.
 * Нужна другая история — бери партияИзFEN.
 */
function партияИзКартинки(картинка, ктоХодит) {
  const строки = Array.isArray(картинка)
    ? картинка.slice()
    : String(картинка).replace(/\r/g, '').split('\n').filter(function (с) { return с.length > 0; });
  if (строки.length !== РЯДОВ) throw new Error('В картинке доски должно быть ровно 8 строк, а пришло ' + строки.length);
  const доска = new Array(КЛЕТОК).fill(ПУСТО);
  for (let i = 0; i < РЯДОВ; i++) {
    const строка = строки[i];
    if (строка.length !== СТОЛБЦОВ) throw new Error('В строке «' + строка + '» должно быть ровно 8 знаков');
    const ряд = РЯДОВ - 1 - i;
    for (let столбец = 0; столбец < СТОЛБЦОВ; столбец++) {
      const знак = строка[столбец];
      if (знак === '.' || знак === ' ') continue;
      const код = ФИГУРА_ПО_БУКВЕ[знак];
      if (код === undefined) throw new Error('Непонятный знак «' + знак + '» в картинке доски');
      доска[клетка(ряд, столбец)] = код;
    }
  }
  const ходит = ктоХодит === ЧЁРНЫЕ ? ЧЁРНЫЕ : БЕЛЫЕ;
  const права = {
    белыеКороткая: доска[E1] === фигураЦвета(КОРОЛЬ, БЕЛЫЕ) && доска[H1] === фигураЦвета(ЛАДЬЯ, БЕЛЫЕ),
    белыеДлинная: доска[E1] === фигураЦвета(КОРОЛЬ, БЕЛЫЕ) && доска[A1] === фигураЦвета(ЛАДЬЯ, БЕЛЫЕ),
    чёрныеКороткая: доска[E8] === фигураЦвета(КОРОЛЬ, ЧЁРНЫЕ) && доска[H8] === фигураЦвета(ЛАДЬЯ, ЧЁРНЫЕ),
    чёрныеДлинная: доска[E8] === фигураЦвета(КОРОЛЬ, ЧЁРНЫЕ) && доска[A8] === фигураЦвета(ЛАДЬЯ, ЧЁРНЫЕ)
  };
  проверитьРасстановку(доска, ходит);
  return собратьПартию(доска, ходит, права, -1, 0, 1);
}

/** Доска словами: восемь строк, верхняя — восьмая горизонталь. */
function картинкаПартии(партия) {
  const строки = [];
  for (let ряд = РЯДОВ - 1; ряд >= 0; ряд--) {
    let строка = '';
    for (let столбец = 0; столбец < СТОЛБЦОВ; столбец++) строка += БУКВЫ_FEN[партия.доска[клетка(ряд, столбец)]];
    строки.push(строка);
  }
  return строки;
}

