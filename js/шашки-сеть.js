'use strict';

/* =====================================================================
   ШАШКИ ПО СЕТИ — МОСТ МЕЖДУ ДОСКОЙ И ОБЩИМ ФАЙЛОМ СВЯЗИ.

   Разговор с сервером ведёт js/сеть.js — один файл на обе игры. Он знает
   про коды комнат, пропуска и длинный опрос; про шашки он не знает ничего.
   Доску рисует js/шашки-экран.js — он не знает ничего про сеть. Между ними
   и стоит этот файл, и в нём нет ни правил игры, ни запросов к серверу.

   Двери наружу — те же, что у дурака (js/сеть.js зовёт их не глядя,
   в какую игру играют):

       window.ИграПоСети = { начать, показатьВид, показатьСвязь,
                             экран, вМеню, идёт }

   Обратно, от доски к серверу, уходит один вид сообщения — ход:

       { действие: 'ход', откуда, куда, побитые, станетДамкой }

   Ровно то, что принимает «сделатьХод» в js/шашки-правила.js. Сервер
   ходу не верит и проверяет его теми же правилами.

   ПОЧЕМУ МОСТ ПОДКЛЮЧАЕТСЯ РАНЬШЕ js/сеть.js. Тот в конце своего файла
   сразу берётся за дело и может немедленно открыть экран — например,
   когда человек пришёл по ссылке-приглашению. Зовёт он для этого мост.
   Не будь моста к той секунде, приглашение открыло бы пустоту.
   ===================================================================== */

(function () {
  /* Имена экранов, которыми говорит js/сеть.js, — дураковы. Три из них
     на странице шашек называются так же (их вид уже описан в общем
     style.css), а два своих переводим. */
  var ПЕРЕВОД_ЭКРАНОВ = {
    'экран-меню': 'экран-режимов',   // у нас это «с кем играть»
    'экран-игры': 'экран-шашек'      // у нас это доска
  };

  /* Идёт ли сейчас партия по сети. Спрашивают и js/сеть.js, и доска. */
  var вПартии = false;

  /** Доска. Появляется в конце страницы, поэтому спрашиваем каждый раз. */
  function доска() {
    return window.ШашкиЭкран || null;
  }

  function режимы() {
    return window.ШашкиРежимы || null;
  }

  /** Полный файл связи (не путать с огрызком, который кладёт «похвастаться»). */
  function связь() {
    var сеть = window.Сеть;
    return сеть && typeof сеть.отправитьХод === 'function' ? сеть : null;
  }

  /* -------------------------------------------------------------------
     ЗНАКИ ВНИМАНИЯ

     Саму панель ставит общий модуль js/онлайн-лобби.js по контексту из
     js/шашки-лобби.js (кнопка «Сказать», полка эмоций и бросков — общий
     набор дурака, js/деберц-знаки.js). Здесь — как в нардах: кнопка
     открывает панель, а каждый новый вид стола уходит в панель.

     Кнопка «Сдаться» у шашек — своя, стоит в разметке страницы заранее
     и управляется чужим файлом js/шашки-экран.js. Мост её не трогает,
     а лишь берёт как соседа, перед которым ставит кнопку «Сказать».
     ------------------------------------------------------------------- */
  var ИМЯ_ИГРЫ = 'шашки';

  function панельЗнаков() {
    var лобби = window.ОнлайнЛобби;
    if (!лобби || typeof лобби.панельЗнаков !== 'function') return null;
    return лобби.панельЗнаков(ИМЯ_ИГРЫ) || null;
  }

  function кнопкаЗнаков() { return document.getElementById('кнопка-эмоции'); }

  function передатьЗнаки(вид) {
    освежитьКнопкуЗнаков(вид);
    var панель = панельЗнаков();
    if (панель && typeof панель.принять === 'function') панель.принять(вид);
  }

  function освежитьКнопкуЗнаков(вид) {
    var кнопка = кнопкаЗнаков();
    if (!кнопка) return;
    var можно = вПартии && Boolean(вид && вид.знакиВниманияЕсть) && Boolean(панельЗнаков());
    кнопка.classList.toggle('скрыт', !можно);
    кнопка.disabled = !можно;
  }

  function нажалиСказать() {
    var панель = панельЗнаков();
    if (вПартии && панель && typeof панель.открыть === 'function') панель.открыть();
  }

  /** Кнопку ставим один раз, рядом с уже существующей на странице «Сдаться». */
  function подключитьКнопкуЗнаков() {
    if (кнопкаЗнаков()) return;
    var сдача = document.getElementById('кнопка-сдаться');
    if (!сдача || !сдача.parentNode) return;
    var кнопка = document.createElement('button');
    кнопка.id = 'кнопка-эмоции';
    кнопка.type = 'button';
    кнопка.className = 'кнопка кнопка--мелкая скрыт';
    кнопка.disabled = true;
    кнопка.textContent = 'Сказать';
    кнопка.addEventListener('click', нажалиСказать);
    сдача.parentNode.insertBefore(кнопка, сдача);
  }

  /* -------------------------------------------------------------------
     Что зовёт js/сеть.js
     ------------------------------------------------------------------- */

  /** За стол сели двое — партия пошла. */
  function начать() {
    вПартии = true;
    var экран = доска();
    if (экран) экран.включитьСеть(отправитьХод);
    подключитьКнопкуЗнаков();
    var где = режимы();
    if (где) где.показатьДоску();
  }

  /**
   * Новое состояние стола. Всё, что здесь делается, — передаём доске:
   * решать, что нарисовать и как показать чужой ход, — её работа.
   */
  function показатьВид(вид) {
    if (!вид) return;
    вПартии = true;
    var экран = доска();
    if (!экран) return;
    экран.включитьСеть(отправитьХод);   // повторный вызов ничего не портит
    подключитьКнопкуЗнаков();
    экран.показатьСетевойВид(вид);
    передатьЗнаки(вид);
  }

  /**
   * Строка над доской: жив ли друг и жива ли связь. Слова приходят готовые
   * из js/сеть.js, вид — 'тревога', 'ожидание' или пусто. Пустой текст
   * прячет строку целиком.
   */
  function показатьСвязь(текст, вид) {
    var строка = document.getElementById('строка-связи');
    if (!строка) return;
    строка.textContent = текст || '';
    строка.classList.toggle('скрыт', !текст);
    строка.classList.toggle('связь--тревога', вид === 'тревога');
    строка.classList.toggle('связь--ожидание', вид === 'ожидание');
  }

  /** Сеть просит показать экран. Имена переводим на свои. */
  function экран(имя) {
    var где = режимы();
    if (!где) return;
    var наш = ПЕРЕВОД_ЭКРАНОВ[имя] || имя;
    /* Уходим с доски — значит, сетевая партия для нас кончилась: дальше
       человек или сидит в комнате, или выбирает соперника заново. */
    if (наш !== 'экран-шашек') отпуститьДоску();
    где.показатьПоИмени(наш);
  }

  /** Сеть закрыла партию (комната пропала, вышли сами). */
  function вМеню() {
    отпуститьДоску();
    var где = режимы();
    if (где) где.показать();
  }

  /**
   * «Назад» с экрана «Вход по коду» (js/сеть.js, назадСоВхода). Вход по
   * коду в шашках открывается только из лобби строкой «Есть код? Войти»,
   * поэтому и назад — снова в лобби, а не на старый экран «Играть
   * с другом» (запасной путь js/сеть.js, куда иначе некуда вернуться).
   * До входа в комнату сетевой партии ещё нет — отпуститьДоску() здесь
   * для симметрии с вМеню() и на случай, если вход открыли не с чистого
   * места.
   */
  function назадСоВхода() {
    отпуститьДоску();
    var где = режимы();
    if (где) где.показать();
  }

  /** Вернуть доску в обычное состояние: дальше играем с ботом или вдвоём. */
  function отпуститьДоску() {
    if (!вПартии) return;
    вПартии = false;
    показатьСвязь('');
    освежитьКнопкуЗнаков(null);
    var экранДоски = доска();
    if (экранДоски) экранДоски.выключитьСеть();
  }

  /* -------------------------------------------------------------------
     Что зовёт доска
     ------------------------------------------------------------------- */

  /**
   * Отправить ход соперника по сети. Обещание никогда не срывается:
   * при любой беде вернётся отказ с причиной, которую доска покажет
   * человеку словами. Свои поля из хода перечислены поимённо — лишнего
   * серверу не отправляем.
   */
  function отправитьХод(ход) {
    var сеть = связь();
    if (!сеть) {
      return Promise.resolve({
        принято: false,
        причина: 'Игра по сети не загрузилась — обновите страницу'
      });
    }
    return сеть.отправитьХод({
      действие: 'ход',
      откуда: ход.откуда,
      куда: ход.куда,
      побитые: ход.побитые,
      станетДамкой: ход.станетДамкой
    }).then(function (ответ) {
      /* Пустой ответ приходит, когда человек успел выйти из партии:
         тогда показывать нечего, и молчание тут — правильный ответ. */
      if (!ответ) return { принято: false, тихо: true };
      if (ответ.ошибкаСвязи) {
        return { принято: false, причина: 'Связь с игрой потеряна — ход не ушёл' };
      }
      return ответ;
    }).catch(function () {
      return { принято: false, причина: 'Ход не удалось отправить' };
    });
  }

  window.ИграПоСети = {
    начать: начать,
    показатьВид: показатьВид,
    показатьСвязь: показатьСвязь,
    экран: экран,
    вМеню: вМеню,
    назадСоВхода: назадСоВхода,
    идёт: function () { return вПартии; }
  };

  /* Наружу — только для доски: ей надо знать, идёт ли сетевая партия,
     когда человек уходит со страницы или начинает партию с ботом. */
  window.ШашкиСеть = {
    идёт: function () { return вПартии; },
    покинуть: function () {
      var сеть = связь();
      отпуститьДоску();
      if (сеть && typeof сеть.покинутьПартию === 'function') сеть.покинутьПартию();
    }
  };
})();
