  /**
   * Край для подсказки раунда 2 (ТЗ 13, Г3е, Г3ж): сперва край, который весь ваш (о нём только что
   * говорила пластина итога); среди равных — тот, где у человека больше всего областей; при равенстве —
   * где областей меньше (ближе к целому); дальше — первый по списку краёв карты.
   * Результат: { текст, край } или null (у человека нет областей ни в одном крае).
   */
  function советПроКрай(партия) {
    const карта = Правила.картаПартии(партия);
    let лучший = null;
    карта.края.forEach(край => {
      const моих = край.области.filter(н => партия.хозяева[н] === КЛЮЧ_ЧЕЛОВЕКА).length;
      if (!моих) return;
      const весь = моих === край.области.length;
      if (!лучший || (весь && !лучший.весь) || (весь === лучший.весь && (моих > лучший.моих ||
        (моих === лучший.моих && край.области.length < лучший.край.области.length)))) {
        лучший = { край: край, моих: моих, весь: весь };
      }
    });
    if (!лучший) return null;
    const { край, моих } = лучший;
    const всего = край.области.length;
    const прибавка = '+' + край.прибавка + ' ' + поЧислу(край.прибавка, 'войско', 'войска', 'войск');
    const область = поЧислу(всего, 'область', 'области', 'областей');
    const текст = моих === всего
      ? 'Обведён ваш край ' + край.название + ': ' + прибавка + ' в раунд, пока все ' + всего + ' ' + область + ' ваши'
      : 'Обведён край ' + край.название + ': держите все ' + всего + ' ' + область +
        ' — '+ прибавка + ' в раунд. У вас ' + моих + ' из ' + всего;
    // Край показывается контуром на карте, а не подписями имён (разбор Г3е, решение 6).
    return { текст: текст, край: край.области.slice() };
  }

