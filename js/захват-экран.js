  function подготовитьРисунки(партия) {
    const КартаВид = window.ЗахватКартаВид;
    if (!КартаВид) return;
    const лёгкий = лёгкийРежим();
    let список;
    try {
      список = КартаВид.нужныеРисунки(партия, лёгкий);
    } catch (ошибка) {
      console.error('Захват: не вышло понять, какие рисунки нужны карте', ошибка);
      return;
    }
    const ключ = (лёгкий ? 'лёгкий|' : 'полный|') + список.map(р => р.имя).join(',');
    if (ключ === ключНабораРисунков) { сказатьСтолуРисунки(рисункиГотовы); return; }
    ключНабораРисунков = ключ;
    картинкиКарты = {};
    рисункиГотовы = false;
    лёгкийНабор = лёгкий;
    сказатьСтолуРисунки(false);
    const номер = ++номерЗагрузки;
    КартаВид.загрузитьРисунки(список).then(итог => {
      if (номер !== номерЗагрузки) return;
      // Что-то не догрузилось: набор не считаем готовым, следующий раунд попробует снова (ошибку пишет карта-вид).
      if (итог.нет && итог.нет.length) ключНабораРисунков = null;
      картинкиКарты = итог.картинки;
      рисункиГотовы = Object.keys(итог.картинки).length > 0;
      сказатьСтолуРисунки(рисункиГотовы);
      нарисоватьКарту();
    });
  }

