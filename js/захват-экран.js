  /* ----- журнал раундов (ТЗ 8.5): лист по касанию пластины -----
     Хранит его память телефона, у каждого режима свой ключ (js/захват-память.js).
     Партию с ботами пишет этот экран, сетевую — сетевой модуль. */

  /** Чей журнал смотреть: того, кто сейчас держит стол. */
  const режимЖурнала = () => (режимСтола === 'сеть' ? 'онлайн' : 'боты');

  function раундыЖурнала() {
    const ж = Память.прочитатьЖурнал(режимЖурнала());
    return ж ? ж.раунды : [];
  }

  /** Новая партия с ботами — журнал заново. Номера партии у ботов нет: метка — миг начала. */
  function начатьЖурналБотов() {
    Память.начатьЖурнал('боты', Date.now(), 'боты');
  }

  /**
   * «Продолжить партию»: журнал ботов собираем из zahvat-save. Там он пишется тем же разбором,
   * что и партия, поэтому совпадает с ней, даже если ключ журнала отстал или пропал.
   */
  function восстановитьЖурналБотов(раунды) {
    const был = Память.прочитатьЖурнал('боты');
    Память.начатьЖурнал('боты', был && был.стол === 'боты' ? был.партия : Date.now(), 'боты');
    раунды.forEach(р => { if (р) Память.добавитьРаундЖурнала(р.номер, р.строки, 'боты'); });
  }

  function строкаЖурнала(текст, класс) {
    const узел = document.createElement('p');
    if (класс) узел.className = класс;
    узел.textContent = текст;
    return узел;
  }

  /**
   * Раунды [{ номер, строки, фразы? }] и готовые строки текста → узлы листа: «Раунд N», под ним
   * фразы «Сказать» (ТЗ 6) и события разбора. Фразы — раньше событий: их говорили, пока раунд
   * шёл, а разбор пришёл в конце. Раунд, где пока только фразы (ЗахватПамять.раундРазобран — нет),
   * ещё не разобран: «Событий не было» у него не пишем.
   */
  function узлыЖурнала(записи) {
    const узлы = [];
    (Array.isArray(записи) ? записи : []).forEach(запись => {
      if (typeof запись === 'string') { узлы.push(строкаЖурнала(запись, 'захват-тихо')); return; }
      if (!запись || !Array.isArray(запись.строки)) return;
      узлы.push(строкаЖурнала('Раунд ' + запись.номер, 'захват-журнал-раунд'));
      (Array.isArray(запись.фразы) ? запись.фразы : []).forEach(текст => узлы.push(строкаЖурнала(String(текст))));
      const разобран = typeof Память.раундРазобран !== 'function' || Память.раундРазобран(запись);
      if (!запись.строки.length && разобран) узлы.push(строкаЖурнала('Событий не было', 'захват-тихо'));
      запись.строки.forEach(текст => узлы.push(строкаЖурнала(String(текст))));
    });
    if (!узлы.length) узлы.push(строкаЖурнала('Раундов ещё не было', 'захват-тихо'));
    return узлы;
  }

  function показатьЖурнал(записи) {
    const список = $('захват-журнал-строки');
    список.replaceChildren(...узлыЖурнала(записи));
    закрытьЛистыСтола();
    $('захват-журнал').classList.remove('скрыт');
    отметитьЛистыЭкрана();
    // Свежий раунд — внизу, старые листаются вверх (ТЗ 8.5): лист открывается на последнем.
    список.scrollTop = список.scrollHeight || 0;
    return true;
  }

  const журналОткрыт = () => !$('захват-журнал').classList.contains('скрыт');

  function закрытьЖурнал() {
    $('захват-журнал').classList.add('скрыт');
    отметитьЛистыЭкрана();
  }

  const пластинаНаЭкране = () => !$('захват-пластина').classList.contains('скрыт');

  /** У ботов сейчас идёт раскрытие: касание пластины — то же, что касание карты, «Пропустить» (ТЗ 8.5). */
  const раскрытиеУБотов = () => режимСтола === 'боты' && !!ход && !!ход.раскрытие;

  /** Палец на пластине не должен стать жестом карты: стол ловит касания выше, на узле карты. */
  function пластинаПалецВниз(событие) {
    if (пластинаНаЭкране() && событие.stopPropagation) событие.stopPropagation();
  }

  /** Касание строки «Раунд N из M» открывает журнал; во время раскрытия у ботов строка молчит. */
  function строкаРаундаНажата() {
    if (раскрытиеУБотов()) return;
    отклик('выбор');
    показатьЖурнал(раундыЖурнала());
  }

  function пластинаНажата(событие) {
    if (!пластинаНаЭкране()) return;
    if (событие.stopPropagation) событие.stopPropagation();
    if (раскрытиеУБотов()) { пропуститьРаскрытие(); return; }
    // Экран не знает, идёт ли у сети раскрытие: сперва спрашиваем сеть. Ответ true — касание
    // она забрала себе (например, пропуск раскрытия), журнал не открываем.
    if (режимСтола === 'сеть' && позватьДверьСети('приКасанииПластины') === true) return;
    отклик('выбор');
    показатьЖурнал(раундыЖурнала());
  }

