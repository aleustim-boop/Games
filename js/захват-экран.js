  /* Рисунки карты. Набор — листы цветов этого стола и своего режима (ЗахватКартаВид.нужныеРисунки).
     Один раз на набор: рестарт с теми же цветами и режимом ничего не грузит заново. Пока картинки
     идут, карта рисуется как есть (без них); битый рисунок карта-вид сам пишет в консоль, замен нет. */
  let картинкиКарты = {};           // готовые картинки набора: имя -> картинка
  let ключНабораРисунков = null;    // набор, который уже грузится или готов
  let рисункиГотовы = false;        // набор догружен: шайбам, пилюлям и значкам стола можно показаться
  let лёгкийНабор = false;          // режим набора: раскладка собирается в том же режиме, что и картинки
  let номерЗагрузки = 0;            // ответ устаревшей загрузки не должен лечь поверх нового набора
  let протяжкаПальцем = null;       // { откуда, x, y }: стрелка за пальцем, пока игрок тянет приказ

  /** «Эффекты стекла» (ТЗ 10): в памяти ключ «эффекты», значение 'лёгкие' — лёгкий набор; всё прочее — полный. */
  const лёгкийРежим = () => Память.взять('эффекты', 'полные') === 'лёгкие';

  /** Стол сам решает, что показать, когда рисунки есть; говорим ему, только пока он у партии с ботами. */
  function сказатьСтолуРисунки(есть) {
    if (стол && режимСтола === 'боты') стол.задатьРисунки(есть);
  }

  function подготовитьРисунки(партия) {
    const КартаВид = window.ЗахватКартаВид;
    if (!КартаВид) return;
    const лёгкий = лёгкийРежим();
    let список;
    try {
      список = КартаВид.нужныеРисунки(партия, лёгкий);
    } catch (ошибка) {
      console.error('Захват: не вышло понять, какие рисунки нужны карте', ошибка);
      return;
    }
    const ключ = (лёгкий ? 'лёгкий|' : 'полный|') + список.map(р => р.имя).join(',');
    if (ключ === ключНабораРисунков) { сказатьСтолуРисунки(рисункиГотовы); return; }
    ключНабораРисунков = ключ;
    картинкиКарты = {};
    рисункиГотовы = false;
    лёгкийНабор = лёгкий;
    сказатьСтолуРисунки(false);
    const номер = ++номерЗагрузки;
    КартаВид.загрузитьРисунки(список).then(итог => {
      if (номер !== номерЗагрузки) return;
      // Что-то не догрузилось: набор не считаем готовым, следующий раунд попробует снова (ошибку пишет карта-вид).
      if (итог.нет && итог.нет.length) ключНабораРисунков = null;
      картинкиКарты = итог.картинки;
      рисункиГотовы = Object.keys(итог.картинки).length > 0;
      сказатьСтолуРисунки(рисункиГотовы);
      нарисоватьКарту();
    });
  }

  /**
   * Перерисовать холст: холст — на весь узел карты (море на всей площади), карта с полем — по центру
   * (ЗахватСтол.местоКарты, то же место берёт слой шайб). Размер в точках экрана × плотность;
   * зум и сдвиг стола и место карты — через setTransform карты-вида.
   */
  function нарисоватьКарту() {
    if (!ход) return;
    const холст = $('захват-холст');
    const ctx = холст && typeof холст.getContext === 'function' ? холст.getContext('2d') : null;
    if (!ctx) return;
    const узелКарты = $('захват-карта');
    const ширинаУзла = ширинаКарты();
    const высотаУзла = узелКарты && узелКарты.clientHeight > 0 ? узелКарты.clientHeight : 0;
    const место = window.ЗахватСтол.местоКарты(ход.наКарте, ширинаУзла, высотаУзла);
    // Эффекты раскрытия (стрелки, вспышки, налив) — только пока идёт раскрытие; потом список пуст.
    const параметрыРаскладки = Object.assign({ ширина: место.ширина, лёгкий: лёгкийНабор }, ход.раскрытие ? эффектыРаскрытия.параметры() : {});
    if (протяжкаПальцем) параметрыРаскладки.протяжка = Object.assign({ кто: КЛЮЧ_ЧЕЛОВЕКА }, протяжкаПальцем);
    const раскладка = window.ЗахватКартаВид.собратьРаскладку(ход.наКарте, параметрыРаскладки);
    const плотность = window.devicePixelRatio || 1;
    const ширинаХолста = Math.round(ширинаУзла * плотность);
    const высотаХолста = Math.round((высотаУзла || раскладка.геометрия.высота) * плотность);
    if (холст.width !== ширинаХолста) холст.width = ширинаХолста;
    if (холст.height !== высотаХолста) холст.height = высотаХолста;
    const вид = ход.вид || { зум: 1, сдвигX: 0, сдвигY: 0 };
    window.ЗахватКартаВид.нарисовать(ctx, раскладка, картинкиКарты, {
      ширинаХолста: ширинаХолста, высотаХолста: высотаХолста, плотность: плотность,
      зум: вид.зум * плотность,
      сдвигX: (место.x + вид.сдвигX) * плотность, сдвигY: (место.y + вид.сдвигY) * плотность
    });
  }

  let кадрЖдёт = false;

  /**
   * Перерисовка на движение пальца: не чаще раза за кадр, рисуется всегда последнее положение
   * (нарисоватьКарту читает свежее состояние). Нет requestAnimationFrame (node-проверки) — рисуем сразу.
   */
  function нарисоватьКартуПоКадру() {
    if (typeof window.requestAnimationFrame !== 'function') { нарисоватьКарту(); return; }
    if (кадрЖдёт) return;
    кадрЖдёт = true;
    window.requestAnimationFrame(() => { кадрЖдёт = false; нарисоватьКарту(); });
  }

  let размерЖдёт = false;

  /**
   * Узел карты поменял размер (поворот телефона, раскрытое окно Telegram, клавиатура): слой шайб,
   * касания и холст считаются заново по новому месту карты, иначе палец попадёт в соседнюю область.
   * Одна дверь для всех событий размера; не чаще раза за кадр. Нет requestAnimationFrame — сразу.
   */
  function приСменеРазмера() {
    if (размерЖдёт) return;
    размерЖдёт = true;
    const пересчитать = () => { размерЖдёт = false; пересчитатьРазмерКарты(); };
    if (typeof window.requestAnimationFrame === 'function') window.requestAnimationFrame(пересчитать);
    else пересчитать();
  }

  /** Стол общий: место и слой пересчитывает он; холст перерисовывает тот, чей сейчас стол. */
  function пересчитатьРазмерКарты() {
    const узел = $('захват-карта');
    // Экран партии спрятан (ширина 0): мерить нечего, при показе слой поставят заново.
    if (!стол || !узел || !(узел.clientWidth > 0)) return;
    if (режимСтола === 'сеть') { стол.обновитьРазмер(узел.clientWidth); позватьДверьСети('приСменеРазмера'); return; }
    if (!ход) return;
    стол.обновитьРазмер(узел.clientWidth);
    нарисоватьКарту();
  }

  /** Все источники смены размера. viewportChanged Telegram — через его официальный WebApp, как в захват-память.js. */
  function слушатьРазмер() {
    window.addEventListener('resize', приСменеРазмера);
    window.addEventListener('orientationchange', приСменеРазмера);
    if (window.visualViewport && typeof window.visualViewport.addEventListener === 'function') {
      window.visualViewport.addEventListener('resize', приСменеРазмера);
    }
    const приложение = window.Telegram && window.Telegram.WebApp;
    if (приложение && typeof приложение.onEvent === 'function') приложение.onEvent('viewportChanged', приСменеРазмера);
    // Узел карты меняется и без смены окна (панель внизу выросла, отступы выреза): следим за ним самим.
    const узел = $('захват-карта');
    if (узел && typeof window.ResizeObserver === 'function') new window.ResizeObserver(приСменеРазмера).observe(узел);
  }

  /* ----- стол и его слушатели ----- */

  /** Позвать дверь сети по имени (слушатель стола или выход); нет такой двери — тишина. */
  function позватьДверьСети(имя, доводы) {
    const дверь = двериСети && двериСети[имя];
    return typeof дверь === 'function' ? дверь.apply(null, доводы || []) : undefined;
  }

  /**
   * Слушатели стола по режиму: в режиме «боты» — слушатели партии с ботами,
   * в режиме «сеть» — одноимённые двери сети. Чужой режим не слышит ничего.
   */
  function поРежиму(слушателиБотов) {
    const итог = {};
    ['приИзменении', 'приГотово', 'приИзменить', 'приВиде', 'приПротяжке', 'приПропуске', 'приДолгомКасанииСОстатком'].forEach(имя => {
      итог[имя] = function () {
        if (режимСтола === 'сеть') return позватьДверьСети(имя, arguments);
        const свой = слушателиБотов[имя];
        return свой ? свой.apply(null, arguments) : undefined;
      };
    });
    return итог;
  }

  function достатьСтол() {
    if (стол) return стол;
    стол = window.ЗахватСтол.создать({
      документ: document,
      рисункиЕсть: false,   // пачки рисунков Кодекса ещё нет: шайбы, пилюли и значки скрыты
      слушатели: поРежиму({
        приИзменении: черновикИзменён,
        приГотово: человекГотов,
        приВиде: вид => { if (ход) { ход.вид = вид; нарисоватьКартуПоКадру(); } },
        // Стол шлёт { из, x, y } пока палец тянет приказ и null, когда отпустил или отменил: стрелку рисует карта-вид.
        приПротяжке: данные => {
          протяжкаПальцем = данные ? { откуда: данные.из, x: данные.x, y: данные.y } : null;
          нарисоватьКартуПоКадру();
        },
        приПропуске: пропуститьРаскрытие,
        приДолгомКасанииСОстатком: открытьПоставитьСюда
      })
    });
    // Стол слушает «Готово» сам; этот слушатель идёт вторым и видит, что стол спросил про остаток.
    $('захват-готово').addEventListener('click', спроситьОбОстатке);
    return стол;
  }

  /**
   * Сеть берёт стол: партия с ботами откладывается тем же путём, что уход в лобби (оставитьПартию).
   * Её окна закрываем: «Да, сдаться» в забытой плашке сдало бы уже сетевую партию,
   * а итог партии с ботами висел бы поверх сетевого стола.
   */
  function столДляСети(двери) {
    if (режимСтола === 'боты') {
      оставитьПартию();
      закрытьОкно('захват-итог');
      закрытьОкно('захват-сдаться-плашка');
      закрытьЖурнал();   // журнал ботов над сетевым столом показывал бы чужую партию
    }
    двериСети = двери || {};
    режимСтола = 'сеть';
    return достатьСтол();
  }

  function отпуститьСтол() {
    // Итог сетевой партии над столом ботов не остаётся: его кнопки вели бы к ушедшей сети.
    if (итогСети) закрытьОкно('захват-итог');
    закрытьЖурнал();
    режимСтола = 'боты';
    двериСети = null;
    спрятатьСказать();
  }

  /**
   * «Сказать» бывает только у сетевой партии (ТЗ 6): кнопку и панель ведёт js/захват-онлайн.js.
   * Стол ушёл к партии с ботами (её начали мимо сети) — кнопку прячем и панель закрываем здесь,
   * иначе над партией с ботами осталась бы кнопка сетевого стола.
   */
  function спрятатьСказать() {
    const кнопка = $('кнопка-эмоции');
    if (кнопка) кнопка.classList.add('скрыт');
    const панель = $('экран-эмоций');
    if (панель && панель.open && typeof панель.close === 'function') панель.close();
  }

