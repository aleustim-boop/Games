  /* ----- раунд ----- */

  /** Новый раунд на столе. черновик — сохранённый (после перезагрузки) или null. */
  function начатьРаунд(черновик) {
    const с = достатьСтол();
    ход.ждёмГотово = true;
    ход.раскрытие = false;
    ход.наКарте = ход.партия;
    ход.черновик = черновик || Правила.пустойЧерновик();
    с.задатьРаскрытие(false);
    с.начатьРаунд(ход.партия, КЛЮЧ_ЧЕЛОВЕКА, инфоСтола(), ход.черновик);
    с.показатьСлой(ширинаКарты());
    нарисоватьКарту();
  }

  /** Черновик бота; бот упал — место играет пустым черновиком, как на сервере (партия не встаёт). */
  function черновикБота(партия, ключ) {
    try {
      return window.ЗахватБот.решить(партия, ключ, ход.выбор.уровень, Math.random);
    } catch (ошибка) {
      console.error('Захват: бот не смог составить черновик, место играет пустым', ошибка);
      return Правила.пустойЧерновик();
    }
  }

  function человекГотов(черновик) {
    if (!ход || !ход.ждёмГотово) return;
    закрытьЛистОстатка();
    if (поставитьСюда) закрытьПоставитьСюда();
    разыгратьРаунд(черновик);
  }

  function построитьРаскрытие(последний, после) {
    return window.ЗахватРаскрытие.построить({
      события: последний.события,
      раунд: последний.раунд,
      карта: Правила.картаПартии(после).ключ,
      имена: ход.имена,
      я: КЛЮЧ_ЧЕЛОВЕКА,
      хозяеваДо: последний.хозяеваДо,
      хозяеваПосле: после.хозяева
    });
  }

  /** «Готово» нажато: все черновики → разбор правилами → сохранение → раскрытие. */
  function разыгратьРаунд(черновикЧеловека) {
    clearTimeout(таймерЧерновика);
    таймерЧерновика = null;
    ход.ждёмГотово = false;
    const до = ход.партия;
    let разбор;
    let последний;
    let расписание;
    try {
      const черновики = {};
      до.игроки.forEach(ключ => {
        if (!Правила.вИгре(до, ключ)) return;
        const свой = ключ === КЛЮЧ_ЧЕЛОВЕКА ? черновикЧеловека : черновикБота(до, ключ);
        // Остаток подкрепления, который никто не поставил, правила ставят сами — как сервер по просрочке.
        черновики[ключ] = Правила.остатокПоПросрочке(до, ключ, свой);
      });
      // Разбираем копию: если правила упадут на середине, настоящая партия останется нетронутой.
      разбор = Правила.разобратьРаунд(копия(до), черновики, Math.random);
      последний = { раунд: разбор.раунд, события: разбор.события, хозяеваДо: до.хозяева.slice() };
      расписание = построитьРаскрытие(последний, разбор.партия);
    } catch (ошибка) {
      console.warn('Захват: не удалось разыграть раунд, партия осталась как была', ошибка);
      вернутьсяКГотово();
      return;
    }
    ход.партия = разбор.партия;
    ход.черновик = Правила.пустойЧерновик();
    ход.последний = последний;
    ход.журнал = ход.журнал.filter(р => р.номер !== разбор.раунд).concat([{ номер: разбор.раунд, строки: расписание.журнал }]);
    // Сразу после разбора, ДО раскрытия (ТЗ 15.5): перезагрузка посреди раскрытия не перебросит кости.
    сохранить();
    начатьРаскрытие(расписание, до);
  }

  /** Раунд не разыгрался: снова ждём «Готово», панель открыта, черновик на столе цел. */
  function вернутьсяКГотово() {
    ход.ждёмГотово = true;
    if (стол.готов()) стол.изменить();
    включитьКнопку('захват-готово', true);
    $('захват-подсказка').textContent = 'Не получилось разыграть раунд — нажмите «Готово» ещё раз';
  }

  /* ----- раскрытие: часы ведёт экран ----- */

  function снятьТаймерыРаскрытия() {
    таймерыРаскрытия.forEach(номер => clearTimeout(номер));
    таймерыРаскрытия = [];
  }

  function начатьРаскрытие(расписание, до) {
    снятьТаймерыРаскрытия();
    clearTimeout(таймерИтога);
    ход.раскрытие = true;
    ход.расписание = расписание;
    ход.наКарте = до;
    стол.задатьРаскрытие(true);
    запертьПанель();
    расписание.шаги.forEach(шаг => { таймерыРаскрытия.push(setTimeout(() => сделатьШаг(шаг), шаг.с)); });
    таймерыРаскрытия.push(setTimeout(закончитьРаскрытие, расписание.всегоМс));
  }

  /** Один шаг расписания. Плюсы, стрелки, капли, вспышки и перекраска — рисунки Кодекса; пока их нет, шаг пропускается. */
  function сделатьШаг(шаг) {
    if (шаг.вид === 'звук') { if (typeof Звук[шаг.имя] === 'function') Звук[шаг.имя](); return; }
    if (шаг.вид === 'пластина') { показатьПластину([шаг.текст]); return; }
    if (шаг.вид === 'итоговая-карта') { показатьИтоговуюКарту(); return; }
    if (шаг.вид === 'итог-раунда') показатьПластину(шаг.строки);
  }

  function показатьИтоговуюКарту() {
    ход.наКарте = ход.партия;
    стол.обновитьПартию(ход.партия);
    запертьПанель();
    нарисоватьКарту();
  }

  /** Касание карты во время раскрытия: сразу итоговый вид и итог раунда (ТЗ 8.5). */
  function пропуститьРаскрытие() {
    if (!ход || !ход.раскрытие) return;
    снятьТаймерыРаскрытия();
    показатьИтоговуюКарту();
    показатьПластину(ход.расписание.итог);
    закончитьРаскрытие();
  }

  function закончитьРаскрытие() {
    снятьТаймерыРаскрытия();
    if (!ход || !ход.раскрытие) return;
    ход.раскрытие = false;
    if (ход.партия.завершена) {
      ЗахватЭкран.партияОкончена(копия(ход.партия));
      return;
    }
    начатьРаунд(null);
    держатьИтог();
  }

  /* ----- начало, продолжение, рестарт и уход ----- */

  /** Снять все часы партии и закрыть её листы (рестарт, уход в лобби). */
  function снятьЧасыПартии() {
    clearTimeout(таймерЧерновика);
    таймерЧерновика = null;
    снятьТаймерыРаскрытия();
    clearTimeout(таймерИтога);
    таймерИтога = null;
    закрытьЛистОстатка();
    if (поставитьСюда) закрытьПоставитьСюда();
    спрятатьПластину();
  }

  /** Ушли с экрана партии: недописанный черновик пишем сразу, часы останавливаем. Вернуться — «Продолжить партию». */
  function оставитьПартию() {
    if (!ход) return;
    if (таймерЧерновика !== null) сохранить();
    снятьЧасыПартии();
    ход = null;
  }

  /** Новая партия. ход: партия, выбор, имена, черновик человека, журнал, последний разобранный раунд и состояние часов. */
  function начатьПартиюСБотами(партия, выбор) {
    снятьЧасыПартии();
    закрытьОкно('захват-итог');
    ход = {
      партия: партия, выбор: выбор, имена: собратьИмена(партия), черновик: Правила.пустойЧерновик(),
      журнал: [], последний: null, ждёмГотово: false, раскрытие: false, расписание: null, наКарте: партия, вид: null
    };
    показатьЭкран('экран-игры');
    сохранить();
    начатьРаунд(null);
  }

  const годноеСохранение = с => !!с && с.версия === ВЕРСИЯ_СОХРАНЕНИЯ && !!с.партия && Array.isArray(с.партия.игроки)
    && Array.isArray(с.партия.хозяева) && с.партия.игроки.indexOf(КЛЮЧ_ЧЕЛОВЕКА) !== -1;

  /** Сохранение не открылось: стираем его, возвращаем игрока в лобби, кнопка «Продолжить» пропадает. */
  function отказатьсяОтСохранения(причина) {
    console.warn('Захват: сохранённую партию продолжить нельзя, сохранение удалено (' + причина + ')');
    снятьЧасыПартии();
    ход = null;
    Память.очиститьСохранение();
    показатьЭкран('экран-лобби');
    освежитьЛобби();
  }

  /** После перезагрузки: итоговая карта последнего разбора и его итог, раунд заново не разыгрывается. */
  function продолжитьПартию(сохранение) {
    if (!годноеСохранение(сохранение)) {
      // Битое сохранение не даст продолжить никогда — убираем его, чтобы кнопка не была мёртвой.
      отказатьсяОтСохранения('чужая версия или нет данных партии');
      return;
    }
    снятьЧасыПартии();
    const партия = сохранение.партия;
    ход = {
      партия: партия, выбор: сохранение.выбор || прочитатьНастройки(), имена: собратьИмена(партия),
      черновик: Правила.пустойЧерновик(), журнал: Array.isArray(сохранение.журнал) ? сохранение.журнал : [],
      последний: сохранение.последний || null, ждёмГотово: false, раскрытие: false, расписание: null, наКарте: партия, вид: null
    };
    if (партия.завершена) {
      показатьЭкран('экран-игры');
      ЗахватЭкран.партияОкончена(копия(партия));
      return;
    }
    try {
      Правила.картаПартии(партия);
      const черновик = сохранение.черновик && Правила.проверитьЧерновик(партия, КЛЮЧ_ЧЕЛОВЕКА, сохранение.черновик).принято
        ? сохранение.черновик : null;
      показатьЭкран('экран-игры');
      начатьРаунд(черновик);
      if (ход.последний) {
        ход.расписание = построитьРаскрытие(ход.последний, партия);
        показатьПластину(ход.расписание.итог);
        держатьИтог();
      }
    } catch (ошибка) {
      отказатьсяОтСохранения(ошибка && ошибка.message ? ошибка.message : 'сбой сборки стола');
    }
  }

  /** Ещё партия без перезагрузки: новичку — снова первая партия, опытному — его настройки. */
  function ещёПартия() {
    начатьПартию(этоПервыйРаз() ? выборНовичка() : прочитатьНастройки());
  }

