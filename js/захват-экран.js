'use strict';
/* =====================================================================
   «ЗАХВАТ»: ЭКРАН, ЧАСТЬ 1 (этап В5) — лобби, настройки партии с ботами,
   «Как играть», рекорды, верхняя строка «‹ ⋯» и общий лист «⋯».

   Чего здесь ещё нет: самой партии (цикл раундов, итог, досмотр) — это В8а/В8б.
   Кнопка «Играть» собирает партию (ЗахватПравила.новаяПартия) и отдаёт её
   заглушке window.ЗахватЭкран.начатьПартиюСБотами — её заполнит В8а.

   Вид здесь не задаётся: из js — только классы, атрибуты и текст.
   Рисунки игры рисует Кодекс, код их только раскладывает.
   Память — только через ЗахватПамять, вибрация — Телеграм.отклик().
   ===================================================================== */
(function () {
  if (typeof document === 'undefined') return;   // под node страницы нет

  const Правила = window.ЗахватПравила, Карты = window.ЗахватКарты;
  const Память = window.ЗахватПамять.открытьДляСтраницы();
  const Звук = window.ЗахватЗвук;
  const $ = id => document.getElementById(id);

  const КЛЮЧ_ЧЕЛОВЕКА = 'человек';
  // Уровни ботов (ТЗ 11). Сохранённый или нажатый уровень не из списка — не принимаем.
  const УРОВНИ = ['лёгкий', 'обычный', 'сложный'];
  const УРОВЕНЬ_ПО_УМОЛЧАНИЮ = 'обычный';
  const СТРОК_В_РЕКОРДАХ = 20;   // ТЗ 8.9: показываем до 20 строк, дома лежит до 50

  // Первый абзац «Как играть» (ТЗ 8.8 п.1): число раундов выбирают, побеждает верхняя половина.
  const ТЕКСТ_ЦЕЛИ = 'Захватите все столицы — или наберите больше всех очков за 10, 15 или 20 раундов '
    + '(выбирают перед партией, обычно 15). Очки: 1 за область, 3 за столицу. '
    + 'Побеждает верхняя половина стола: вдвоём и втроём — первое место, вчетвером и впятером — '
    + 'два первых, вшестером — три первых. Кто выбыл или сдался, не побеждает.';

  /* ---------- заглушки: их заполнят следующие этапы ---------- */

  const ЗахватЭкран = {
    /** В8а: запустить цикл партии с ботами. партия — результат новаяПартия, выбор — { мест, уровень, раундовЗахвата, новичок }. */
    начатьПартиюСБотами: function (партия, выбор) {},
    /** В8а: продолжить партию из zahvat-save. */
    продолжитьПартию: function (сохранение) {},
    /** В8б: игрок подтвердил «Да, сдаться». */
    сдатьсяВПартии: function () {}
  };
  window.ЗахватЭкран = ЗахватЭкран;

  /* ---------- окна и экраны ---------- */

  function открытьОкно(id) {
    const окно = $(id);
    if (окно && !окно.open) окно.showModal();
  }

  function закрытьОкно(id) {
    const окно = $(id);
    if (окно && окно.open) окно.close();
  }

  function показатьЭкран(id) {
    document.querySelectorAll('.экран').forEach(е => е.classList.toggle('экран--виден', е.id === id));
    if (id === 'экран-лобби') освежитьЛобби();
    if (window.Телеграм && window.Телеграм.показатьСтрелку) window.Телеграм.показатьСтрелку(назад);
    if (лист) лист.освежитьКнопкуНастроек(id);
  }

  function назад() {
    const окно = document.querySelector('dialog[open]');
    if (окно) { окно.close(); return; }
    if (лист && лист.открыт()) { лист.закрыть(); return; }
    if ($('экран-лобби').classList.contains('экран--виден')) { location.href = 'index.html'; return; }
    показатьЭкран('экран-лобби');
  }

  const отклик = вид => { if (window.Телеграм && window.Телеграм.отклик) window.Телеграм.отклик(вид); };

  /* ---------- настройки партии с ботами (ТЗ 8.2) ---------- */

  const этоПервыйРаз = () => !Память.взять('выучено', 0);

  /** Сохранённый выбор; всё негодное заменяется обычным значением. */
  function прочитатьНастройки() {
    const сохранено = Память.взять('боты', null) || {};
    const мин = Правила.ЧИСЛА.мест.мин, макс = Правила.ЧИСЛА.мест.макс;
    return {
      мест: Number.isInteger(сохранено.мест) && сохранено.мест >= мин && сохранено.мест <= макс
        ? сохранено.мест : Правила.ЧИСЛА.мест.поУмолчанию,
      уровень: УРОВНИ.indexOf(сохранено.уровень) !== -1 ? сохранено.уровень : УРОВЕНЬ_ПО_УМОЛЧАНИЮ,
      раундовЗахвата: Правила.ЧИСЛА.раундов.варианты.indexOf(сохранено.раундовЗахвата) !== -1
        ? сохранено.раундовЗахвата : Правила.ЧИСЛА.раундов.обычно
    };
  }

  let настройки = прочитатьНастройки();

  function сохранитьНастройки() {
    Память.положить('боты', { мест: настройки.мест, уровень: настройки.уровень, раундовЗахвата: настройки.раундовЗахвата });
  }

  /** Подпись серым: карта по числу мест, раундов в ней нет — они в своей строке. */
  function подписьКарты(мест) {
    const карта = Карты.КАРТЫ[Правила.ЧИСЛА.составы[мест].карта];
    return 'Карта: ' + карта.название + ' · ' + карта.области.length + ' областей';
  }

  /** Отметить кнопку группы с этим значением, остальные снять. */
  function отметитьВыбор(группа, значение) {
    группа.querySelectorAll('button').forEach(кнопка => {
      кнопка.setAttribute('aria-checked', кнопка.getAttribute('data-значение') === String(значение) ? 'true' : 'false');
    });
  }

  /** Нажатие на кнопку группы: что нажато — отдаём в дело(значение). */
  function слушатьГруппу(группа, дело) {
    группа.addEventListener('click', событие => {
      const кнопка = событие.target && событие.target.closest ? событие.target.closest('button') : null;
      if (!кнопка || !группа.contains(кнопка)) return;
      отклик('выбор');
      дело(кнопка.getAttribute('data-значение'));
    });
  }

  /** Строка пилюль «Раундов: 10 · 15 · 20»: в разметке её нет, делаем здесь из чисел правил. Новичку её нет. */
  function поставитьСтрокуРаундов() {
    let строка = $('захват-строка-раундов');
    if (этоПервыйРаз()) { if (строка) строка.remove(); return; }
    if (!строка) {
      строка = document.createElement('div');
      строка.id = 'захват-строка-раундов';
      строка.className = 'захват-выбор-параметра';
      const подпись = document.createElement('strong');
      подпись.textContent = 'Раундов';
      const группа = document.createElement('div');
      группа.id = 'захват-выбор-раунды';
      группа.className = 'захват-выбор-числа';
      группа.setAttribute('role', 'radiogroup');
      группа.setAttribute('aria-label', 'Раундов');
      Правила.ЧИСЛА.раундов.варианты.forEach(число => {
        const кнопка = document.createElement('button');
        кнопка.setAttribute('type', 'button');
        кнопка.setAttribute('role', 'radio');
        кнопка.setAttribute('aria-checked', 'false');
        кнопка.setAttribute('data-значение', String(число));
        кнопка.textContent = String(число);
        группа.appendChild(кнопка);
      });
      строка.append(подпись, группа);
      const подписьКарты = $('захват-подпись-карты');
      подписьКарты.parentNode.insertBefore(строка, подписьКарты);
      слушатьГруппу(группа, значение => {
        настройки.раундовЗахвата = Number(значение);
        сохранитьНастройки();
        освежитьНастройки();
      });
    }
  }

  /** Показать на экране то, что лежит в настройках. */
  function освежитьНастройки() {
    отметитьВыбор($('захват-выбор-число'), настройки.мест);
    отметитьВыбор($('захват-выбор-уровень'), настройки.уровень);
    const раунды = $('захват-выбор-раунды');
    if (раунды) отметитьВыбор(раунды, настройки.раундовЗахвата);
    $('захват-подпись-карты').textContent = подписьКарты(настройки.мест);
  }

  function открытьНастройки() {
    настройки = прочитатьНастройки();
    поставитьСтрокуРаундов();
    освежитьНастройки();
    показатьЭкран('захват-настройки');
  }

  /* ---------- старт партии ---------- */

  /** Партия для выбора. Человек всегда в списке людей — иначе правило «все люди выбыли» не сработает. */
  function собратьПартию(выбор) {
    const игроки = [КЛЮЧ_ЧЕЛОВЕКА];
    for (let н = 1; н < выбор.мест; н++) игроки.push('бот-' + н);
    const настройкиПартии = { игроки: игроки, люди: [КЛЮЧ_ЧЕЛОВЕКА], сейчас: Date.now() };
    if (выбор.новичок) настройкиПартии.новичок = КЛЮЧ_ЧЕЛОВЕКА;
    else настройкиПартии.раундовЗахвата = выбор.раундовЗахвата;
    return Правила.новаяПартия(настройкиПартии, Math.random);
  }

  function начатьПартию(выбор) {
    ЗахватЭкран.начатьПартиюСБотами(собратьПартию(выбор), выбор);
  }

  /** Первая партия в жизни (ТЗ 8.2, 13): сразу в игру — 3 места, лёгкие боты, Остров, 10 раундов. */
  function выборНовичка() {
    return { мест: Правила.ЧИСЛА.перваяПартия.мест, уровень: 'лёгкий', раундовЗахвата: Правила.ЧИСЛА.перваяПартия.раундов, новичок: true };
  }

  function нажатоИгратьСБотами() {
    if (этоПервыйРаз()) начатьПартию(выборНовичка());
    else открытьНастройки();
  }

  function нажатоНачать() {
    начатьПартию({ мест: настройки.мест, уровень: настройки.уровень, раундовЗахвата: настройки.раундовЗахвата, новичок: false });
  }

  /* ---------- лобби ---------- */

  function освежитьЛобби() {
    const имя = window.Телеграм && window.Телеграм.имяИгрока ? window.Телеграм.имяИгрока() : '';
    $('лобби-имя').textContent = имя || 'Вы';
    $('захват-продолжить').classList.toggle('скрыт', !Память.прочитатьСохранение());
  }

  /* ---------- «Как играть» и рекорды ---------- */

  function поставитьТекстЦели() {
    const абзац = $('захват-справка').querySelector('p');
    if (!абзац) return;
    const жирный = document.createElement('strong');
    жирный.textContent = 'Цель.';
    абзац.replaceChildren(жирный, document.createTextNode(' ' + ТЕКСТ_ЦЕЛИ));
  }

  const двеЦифры = число => (число < 10 ? '0' : '') + число;

  /** «01.10, 14:05» — по часам телефона, как записано в рекорде. */
  function датаСтрокой(мс) {
    const д = new Date(мс);
    return двеЦифры(д.getDate()) + '.' + двеЦифры(д.getMonth() + 1) + ', ' + двеЦифры(д.getHours()) + ':' + двеЦифры(д.getMinutes());
  }

  function строкаРекорда(р) {
    const узел = document.createElement('p');
    узел.className = 'захват-рекорды-строка';
    узел.textContent = датаСтрокой(р.когда) + ' · ' + (р.режим === 'боты' ? 'с ботами' : 'онлайн') + ' · ' + р.мест
      + ' · ' + р.место + ' из ' + р.мест + ' · очки ' + р.очки + ' · раундов ' + р.раундов;
    return узел;
  }

  function показатьРекорды() {
    const таблица = Память.рекорды().slice(0, СТРОК_В_РЕКОРДАХ);
    const итоги = Память.сводка();
    // «Первых мест» — партии с местом 1: побед теперь больше, чем первых мест (ТЗ 5, 8.9).
    $('захват-рекорды-сводка').textContent = 'Сыграно ' + итоги.сыграно + ' · Первых мест ' + итоги.побед + ' · Лучший счёт ' + итоги.лучшийСчёт;
    const список = $('захват-рекорды-список');
    if (!таблица.length) {
      const пусто = document.createElement('p');
      пусто.className = 'захват-тихо';
      пусто.textContent = 'Здесь появятся ваши партии.';
      список.replaceChildren(пусто);
    } else {
      список.replaceChildren(...таблица.map(строкаРекорда));
    }
    открытьОкно('захват-рекорды');
  }

  /* ---------- общий лист «⋯» ---------- */

  // Строка «Вибрация» нужна, только если телефону есть чем вибрировать.
  const естьВибрация = () => !!(window.Телеграм && typeof window.Телеграм.вибрацияДоступна === 'function'
    && typeof window.Телеграм.включитьВибрацию === 'function'
    && typeof window.Телеграм.вибрацияВключена === 'function'
    && window.Телеграм.вибрацияДоступна());

  const идётПартия = () => $('экран-игры').classList.contains('экран--виден');

  // «Оформления» у игры нет (нет своего экрана) — двери нет, строки в листе нет.
  const лист = window.ЛистЕщё.подключить({
    экраныСЛистом: ['экран-лобби', 'захват-настройки', 'экран-игры'],
    двери: {
      вМеню: { действие: назад },
      какИграть: { действие: () => открытьОкно('захват-справка') },
      звук: { состояние: () => Звук.включён() ? 'вкл' : 'выкл', действие: () => { Звук.переключить(); } },
      вибрация: {
        доступна: естьВибрация,
        состояние: () => естьВибрация() && window.Телеграм.вибрацияВключена() ? 'вкл' : 'выкл',
        действие: () => { if (естьВибрация()) window.Телеграм.включитьВибрацию(!window.Телеграм.вибрацияВключена()); }
      },
      рекорды: { действие: показатьРекорды },
      // «Сдаться» — только в партии; сам лист вопроса не задаёт, плашку показываем мы.
      сдаться: { видна: идётПартия, действие: () => открытьОкно('захват-сдаться-плашка') }
    }
  });

  /* ---------- привязка кнопок ---------- */

  document.querySelectorAll('[data-назад]').forEach(к => к.addEventListener('click', назад));
  document.querySelectorAll('[data-меню]').forEach(к => к.addEventListener('click', () => { if (лист) лист.открыть(); }));

  $('захват-боты').addEventListener('click', нажатоИгратьСБотами);
  $('захват-начать').addEventListener('click', нажатоНачать);
  $('захват-правила-лобби').addEventListener('click', () => открытьОкно('захват-справка'));
  $('захват-продолжить').addEventListener('click', () => {
    const сохранение = Память.прочитатьСохранение();
    if (сохранение) ЗахватЭкран.продолжитьПартию(сохранение);
  });
  $('лобби-профиль').addEventListener('click', () => { if (window.ЭкранПрофиля) window.ЭкранПрофиля.открыть('захват'); });
  $('захват-сдаться-да').addEventListener('click', () => { закрытьОкно('захват-сдаться-плашка'); ЗахватЭкран.сдатьсяВПартии(); });

  слушатьГруппу($('захват-выбор-число'), значение => {
    настройки.мест = Number(значение);
    сохранитьНастройки();
    освежитьНастройки();
  });
  слушатьГруппу($('захват-выбор-уровень'), значение => {
    if (УРОВНИ.indexOf(значение) === -1) return;
    настройки.уровень = значение;
    сохранитьНастройки();
    освежитьНастройки();
  });

  поставитьТекстЦели();
  window.addEventListener('load', () => { if (window.Телеграм && window.Телеграм.показатьСтрелку) window.Телеграм.показатьСтрелку(назад); });
  // Облако могло знать больше, чем телефон: когда ответит — перерисовать лобби.
  Память.подтянуть(изменилось => { if (изменилось) освежитьЛобби(); });
  показатьЭкран('экран-лобби');
})();
