    /** Ещё одна партия без перезагрузки страницы — с теми же настройками. */
    ещёПартия: function () { ещёПартия(); },
    /** Партия кончилась: рекорд, очистка zahvat-save, билет — и только потом лист или итог. партия — с полями конца (15.2). */
    партияОкончена: function (партия) { партияОкончена(партия); },
    /** Игрок подтвердил «Да, сдаться». */
