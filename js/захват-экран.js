  // Сколько px снизу окна карты занято пилюлей: от верха пилюли до низа окна и ещё её зазор 8 px.
  // Пилюли нет, она скрыта или рамок нет (node) — 0, карта лежит как раньше.
  function занятыйПилюлейНиз() {
    const пилюля = $('захват-совет');
    const окно = $('захват-карта');
    if (!пилюля || !окно || typeof пилюля.getBoundingClientRect !== 'function' || typeof окно.getBoundingClientRect !== 'function') return 0;
    if (пилюля.classList.contains('скрыт')) return 0;
    const рамкаПилюли = пилюля.getBoundingClientRect();
    if (!(рамкаПилюли.height > 0)) return 0;
    const низОкна = окно.getBoundingClientRect().top + (окно.clientTop || 0) + окно.clientHeight;
    return Math.max(0, Math.round(низОкна - рамкаПилюли.top + ЗАЗОР_ПИЛЮЛИ_PX));
  }

  // Пилюля показана, ушла или сменила высоту: карта вписывается над ней, холст рисуется по новому месту.
  // За сетевым столом пилюлю ведёт сеть и место карты считает она — там отступ всегда 0.
  function подвинутьКартуОтПилюли() {
    if (!стол) return;
    const нужный = режимСтола === 'боты' ? занятыйПилюлейНиз() : 0;
    // Своё число меняем только вместе со столом: холст и слой шайб обязаны брать одно и то же место.
    if (!стол.задатьЗанятыйНиз(нужный)) return;
    занятыйНизКарты = нужный;
    if (режимСтола === 'боты') нарисоватьКарту();
  }

