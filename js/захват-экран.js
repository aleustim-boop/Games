  function открытьОкно(id) {
    const окно = $(id);
    if (окно && !окно.open) окно.showModal();
  }

  function закрытьОкно(id) {
    const окно = $(id);
    if (окно && окно.open) окно.close();
  }

  function показатьЭкран(id) {
    if (id !== 'экран-игры') оставитьПартию();
    document.querySelectorAll('.экран').forEach(е => е.classList.toggle('экран--виден', е.id === id));
    if (id === 'экран-лобби') освежитьЛобби();
    if (window.Телеграм && window.Телеграм.показатьСтрелку) window.Телеграм.показатьСтрелку(назад);
    if (лист) лист.освежитьКнопкуНастроек(id);
  }

  function назад() {
    const окно = document.querySelector('dialog[open]');
    if (окно) { окно.close(); return; }
    if (лист && лист.открыт()) { лист.закрыть(); return; }
    if ($('экран-лобби').classList.contains('экран--виден')) { location.href = 'index.html'; return; }
    // За сетевым столом «‹» и «В меню» — выход из стола сети, а не уход из партии с ботами.
    if (режимСтола === 'сеть' && идётПартия()) { позватьДверьСети('выйти'); return; }
    показатьЭкран('экран-лобби');
  }

  const отклик = вид => { if (window.Телеграм && window.Телеграм.отклик) window.Телеграм.отклик(вид); };

  /* ---------- настройки партии с ботами (ТЗ 8.2) ---------- */

  const этоПервыйРаз = () => !Память.взять('выучено', 0);

  /** Сохранённый выбор; всё негодное заменяется обычным значением. */
  function прочитатьНастройки() {
    const сохранено = Память.взять('боты', null) || {};
    const мин = Правила.ЧИСЛА.мест.мин, макс = Правила.ЧИСЛА.мест.макс;
    return {
      мест: Number.isInteger(сохранено.мест) && сохранено.мест >= мин && сохранено.мест <= макс
        ? сохранено.мест : Правила.ЧИСЛА.мест.поУмолчанию,
      уровень: УРОВНИ.indexOf(сохранено.уровень) !== -1 ? сохранено.уровень : УРОВЕНЬ_ПО_УМОЛЧАНИЮ,
      раундовЗахвата: Правила.ЧИСЛА.раундов.варианты.indexOf(сохранено.раундовЗахвата) !== -1
        ? сохранено.раундовЗахвата : Правила.ЧИСЛА.раундов.обычно
    };
  }

  let настройки = прочитатьНастройки();

  function сохранитьНастройки() {
    Память.положить('боты', { мест: настройки.мест, уровень: настройки.уровень, раундовЗахвата: настройки.раундовЗахвата });
  }

  /** Подпись серым: карта по числу мест, раундов в ней нет — они в своей строке. */
  function подписьКарты(мест) {
    const карта = Карты.КАРТЫ[Правила.ЧИСЛА.составы[мест].карта];
    return 'Карта: ' + карта.название + ' · ' + карта.области.length + ' областей';
  }

  /** Отметить кнопку группы с этим значением, остальные снять. */
  function отметитьВыбор(группа, значение) {
    группа.querySelectorAll('button').forEach(кнопка => {
      кнопка.setAttribute('aria-checked', кнопка.getAttribute('data-значение') === String(значение) ? 'true' : 'false');
    });
  }

  /** Нажатие на кнопку группы: что нажато — отдаём в дело(значение). */
  function слушатьГруппу(группа, дело) {
    группа.addEventListener('click', событие => {
      const кнопка = событие.target && событие.target.closest ? событие.target.closest('button') : null;
      if (!кнопка || !группа.contains(кнопка)) return;
      отклик('выбор');
      дело(кнопка.getAttribute('data-значение'));
    });
  }

  /** Строка пилюль «Раундов: 10 · 15 · 20»: в разметке её нет, делаем здесь из чисел правил. Новичку её нет. */
  function поставитьСтрокуРаундов() {
    let строка = $('захват-строка-раундов');
    if (этоПервыйРаз()) { if (строка) строка.remove(); return; }
    if (!строка) {
      строка = document.createElement('div');
      строка.id = 'захват-строка-раундов';
      строка.className = 'захват-выбор-параметра';
      const подпись = document.createElement('strong');
      подпись.textContent = 'Раундов';
      const группа = document.createElement('div');
      группа.id = 'захват-выбор-раунды';
      группа.className = 'захват-выбор-числа';
      группа.setAttribute('role', 'radiogroup');
      группа.setAttribute('aria-label', 'Раундов');
      Правила.ЧИСЛА.раундов.варианты.forEach(число => {
        const кнопка = document.createElement('button');
        кнопка.setAttribute('type', 'button');
        кнопка.setAttribute('role', 'radio');
        кнопка.setAttribute('aria-checked', 'false');
        кнопка.setAttribute('data-значение', String(число));
        кнопка.textContent = String(число);
        группа.appendChild(кнопка);
      });
      строка.append(подпись, группа);
      const подписьКарты = $('захват-подпись-карты');
      подписьКарты.parentNode.insertBefore(строка, подписьКарты);
      слушатьГруппу(группа, значение => {
        настройки.раундовЗахвата = Number(значение);
        сохранитьНастройки();
        освежитьНастройки();
      });
    }
  }

  /** Показать на экране то, что лежит в настройках. */
  function освежитьНастройки() {
    отметитьВыбор($('захват-выбор-число'), настройки.мест);
    отметитьВыбор($('захват-выбор-уровень'), настройки.уровень);
    const раунды = $('захват-выбор-раунды');
    if (раунды) отметитьВыбор(раунды, настройки.раундовЗахвата);
    $('захват-подпись-карты').textContent = подписьКарты(настройки.мест);
  }

  function открытьНастройки() {
    настройки = прочитатьНастройки();
    поставитьСтрокуРаундов();
    освежитьНастройки();
    показатьЭкран('захват-настройки');
  }

  /* ---------- старт партии ---------- */

  /** Партия для выбора. Человек всегда в списке людей — иначе правило «все люди выбыли» не сработает. */
  function собратьПартию(выбор) {
    const игроки = [КЛЮЧ_ЧЕЛОВЕКА];
    for (let н = 1; н < выбор.мест; н++) игроки.push('бот-' + н);
    const настройкиПартии = { игроки: игроки, люди: [КЛЮЧ_ЧЕЛОВЕКА], сейчас: Date.now() };
    if (выбор.новичок) настройкиПартии.новичок = КЛЮЧ_ЧЕЛОВЕКА;
    else настройкиПартии.раундовЗахвата = выбор.раундовЗахвата;
    return Правила.новаяПартия(настройкиПартии, Math.random);
  }

  function начатьПартию(выбор) {
    // ТЗ 13: первая партия — «выучено» пишется сразу, доиграна она или нет; дальше выбор по настройкам.
    if (выбор.новичок) Память.положить('выучено', 1);
    ЗахватЭкран.начатьПартиюСБотами(собратьПартию(выбор), выбор);
  }

  /** Первая партия в жизни (ТЗ 8.2, 13): сразу в игру — 3 места, лёгкие боты, Остров, 10 раундов. */
  function выборНовичка() {
    return { мест: Правила.ЧИСЛА.перваяПартия.мест, уровень: 'лёгкий', раундовЗахвата: Правила.ЧИСЛА.перваяПартия.раундов, новичок: true };
  }

  function нажатоИгратьСБотами() {
    if (этоПервыйРаз()) начатьПартию(выборНовичка());
    else открытьНастройки();
  }

  function нажатоНачать() {
    начатьПартию({ мест: настройки.мест, уровень: настройки.уровень, раундовЗахвата: настройки.раундовЗахвата, новичок: false });
  }

  /* ---------- партия с ботами без сети (В8а, ТЗ 15.5) ----------
     Раунд: человек правит черновик → «Готово» → боты составляют свои → правила
     разбирают раунд → zahvat-save пишется СРАЗУ → раскрытие по расписанию
     js/захват-раскрытие.js (часы ведёт экран) → следующий раунд или конец партии. */

  const ВЕРСИЯ_СОХРАНЕНИЯ = 1;
  // Ширина карты, пока узел ещё не измерен (поддельный документ, экран ещё скрыт): ширина колонки игры.
  const ШИРИНА_КАРТЫ_ЗАПАС = 358;
  // Итог раунда держится в новом раунде до касания или 5 секунд (ТЗ 8.5).
  const ДЕРЖАТЬ_ИТОГ_МС = 5000;
  // Рисунки Кодекса для карты ещё не приняты (этап Г1): холст пока пустой, заглушек код не рисует.
  const РИСУНКИ_КАРТЫ = {};
  const ТЕКСТ_РАСКРЫТИЯ = 'Раскрытие раунда — коснитесь карты, чтобы пропустить';

  // Подсказки первой партии (ТЗ 13), по порядку. Пульсация своих областей и салатовый пунктир
  // на ничьей соседней — Г3: нужны рисунки и метки стола в js/захват-стол.js.
  const СОВЕТЫ = {
    поставить: 'Это ваши области. Коснитесь своей — поставите войско. Осталось: ',
    удар: 'Теперь проведите пальцем от своей области к соседней — это удар',
    готово: 'Нажмите «Готово». Соперники ходят одновременно с вами',
    раскрытие: 'Все приказы исполняются разом — смотрите, кто куда ударил',
    итог: 'Держите целый край — получите прибавку. Удачи!'
  };

  let стол = null;                  // стол создаётся при первой партии и живёт до закрытия страницы
  // Стол на странице один, а слушают его двое: партия с ботами и сеть (js/захват-онлайн.js).
  // Каждый ЗахватСтол.создать вешает обработчики на те же кнопки, поэтому второго стола нет,
  // а чужой режим молчит: иначе сеть портила бы zahvat-save, а «Сдаться» сдавало бы не ту партию.
  let режимСтола = 'боты';          // 'боты' | 'сеть'
  let двериСети = null;             // слушатели стола и выход из партии от сети (столДляСети)
  let ход = null;                   // идущая партия (см. начатьПартиюСБотами)
  let таймерЧерновика = null;
  let таймерыРаскрытия = [];
  let таймерИтога = null;
  let поставитьСюда = null;         // открытый лист «Поставить сюда»: { область, число, максимум }
  let таймерДосмотра = null;
  let номерИтога = 0;               // ответ рейтинга прошлой партии не должен лечь в итог новой

  const копия = объект => JSON.parse(JSON.stringify(объект));

  function имяЧеловека() {
    const имя = window.Телеграм && window.Телеграм.имяИгрока ? window.Телеграм.имяИгрока() : '';
    return имя || 'Вы';
  }

  /** Имена мест для строк раскрытия и полосы игроков: человек — из Telegram, боты по номеру места. */
  function собратьИмена(партия) {
    const имена = {};
    партия.игроки.forEach((ключ, номер) => { имена[ключ] = ключ === КЛЮЧ_ЧЕЛОВЕКА ? имяЧеловека() : 'Бот ' + номер; });
    return имена;
  }

  function инфоСтола() {
    const боты = {};
    ход.партия.игроки.forEach(ключ => { if (ключ !== КЛЮЧ_ЧЕЛОВЕКА) боты[ключ] = true; });
    return { имена: ход.имена, готовы: {}, боты: боты, спят: {} };
  }

  const поставлено = черновик => Object.keys(черновик.расстановка).reduce((сумма, к) => сумма + черновик.расстановка[к], 0);

  /** Сколько войск подкрепления человек ещё не поставил в черновике стола. */
  function остатокЧеловека() {
    return (ход.партия.подкрепление[КЛЮЧ_ЧЕЛОВЕКА] || 0) - поставлено(стол.черновик());
  }

  /* ----- сохранение (ТЗ 15.5) ----- */

  /** Всё, что нужно для «Продолжить партию»: карта после последнего разбора, его события и журнал. */
  function сохранить() {
    if (!ход) return;
    Память.записатьСохранение({
      версия: ВЕРСИЯ_СОХРАНЕНИЯ,
      партия: ход.партия,
      выбор: ход.выбор,
      черновик: ход.черновик,
      последний: ход.последний,
      журнал: ход.журнал
    });
  }

  function сохранитьЧерновик() {
    таймерЧерновика = null;
    сохранить();
  }

  /** Срочная запись при уходе со страницы: только если правка ещё ждёт своих 400 мс. */
  function записатьЧерновикСрочно() {
    if (!ход || таймерЧерновика === null) return;
    clearTimeout(таймерЧерновика);
    сохранитьЧерновик();
  }

  /** Правка черновика: пишем не сразу, а через 400 мс тишины — последняя правка побеждает. */
  function черновикИзменён(черновик) {
    if (!ход || !ход.ждёмГотово) return;
    ход.черновик = черновик;
    освежитьСовет();
    clearTimeout(таймерЧерновика);
    таймерЧерновика = setTimeout(сохранитьЧерновик, Правила.ЧИСЛА.задержкаЧерновикаМс);
  }

  /* ----- холст карты: только готовые рисунки через карту-вид ----- */

  function ширинаКарты() {
    const узел = $('захват-карта');
    return узел && узел.clientWidth > 0 ? узел.clientWidth : ШИРИНА_КАРТЫ_ЗАПАС;
  }

  /** Перерисовать холст: размер в точках экрана × плотность, зум и сдвиг стола — через setTransform карты-вида. */
  function нарисоватьКарту() {
    if (!ход) return;
    const холст = $('захват-холст');
    const ctx = холст && typeof холст.getContext === 'function' ? холст.getContext('2d') : null;
    if (!ctx) return;
    const ширина = ширинаКарты();
    const раскладка = window.ЗахватКартаВид.собратьРаскладку(ход.наКарте, { ширина: ширина });
    const плотность = window.devicePixelRatio || 1;
    const ширинаХолста = Math.round(ширина * плотность);
    const высотаХолста = Math.round(раскладка.геометрия.высота * плотность);
    if (холст.width !== ширинаХолста) холст.width = ширинаХолста;
    if (холст.height !== высотаХолста) холст.height = высотаХолста;
    const вид = ход.вид || { зум: 1, сдвигX: 0, сдвигY: 0 };
    window.ЗахватКартаВид.нарисовать(ctx, раскладка, РИСУНКИ_КАРТЫ, {
      ширинаХолста: ширинаХолста, высотаХолста: высотаХолста,
      зум: вид.зум * плотность, сдвигX: вид.сдвигX * плотность, сдвигY: вид.сдвигY * плотность
    });
  }

