  const двеЦифры = число => (число < 10 ? '0' : '') + число;

  /** «01.10, 14:05» — по часам телефона, как записано в рекорде. */
  function датаСтрокой(мс) {
    const д = new Date(мс);
    return двеЦифры(д.getDate()) + '.' + двеЦифры(д.getMonth() + 1) + ', ' + двеЦифры(д.getHours()) + ':' + двеЦифры(д.getMinutes());
  }

