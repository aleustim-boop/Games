  /**
   * Узел карты поменял размер (поворот телефона, раскрытое окно Telegram, клавиатура): слой шайб,
   * касания и холст считаются заново по новому месту карты, иначе палец попадёт в соседнюю область.
   * Одна дверь для всех событий размера; не чаще раза за кадр. Нет requestAnimationFrame — сразу.
   */
  function приСменеРазмера() {
    if (размерЖдёт) return;
    размерЖдёт = true;
    const пересчитать = () => { размерЖдёт = false; пересчитатьРазмерКарты(); };
    if (typeof window.requestAnimationFrame === 'function') window.requestAnimationFrame(пересчитать);
    else пересчитать();
  }

  /** Стол общий: место и слой пересчитывает он; холст перерисовывает тот, чей сейчас стол. */
  function пересчитатьРазмерКарты() {
    const узел = $('захват-карта');
    // Экран партии спрятан (ширина 0): мерить нечего, при показе слой поставят заново.
    if (!стол || !узел || !(узел.clientWidth > 0)) return;
    if (режимСтола === 'сеть') { стол.обновитьРазмер(узел.clientWidth); позватьДверьСети('приСменеРазмера'); return; }
    if (!ход) return;
    стол.обновитьРазмер(узел.clientWidth);
    подвинутьКартуОтПилюли();   // от ширины зависит и высота пилюли (текст переносится иначе)
    нарисоватьКарту();
  }

  /** Все источники смены размера. viewportChanged Telegram — через его официальный WebApp, как в захват-память.js. */
  function слушатьРазмер() {
    window.addEventListener('resize', приСменеРазмера);
    window.addEventListener('orientationchange', приСменеРазмера);
    if (window.visualViewport && typeof window.visualViewport.addEventListener === 'function') {
      window.visualViewport.addEventListener('resize', приСменеРазмера);
    }
    const приложение = window.Telegram && window.Telegram.WebApp;
    if (приложение && typeof приложение.onEvent === 'function') приложение.onEvent('viewportChanged', приСменеРазмера);
    // Узел карты меняется и без смены окна (панель внизу выросла, отступы выреза): следим за ним самим.
    const узел = $('захват-карта');
    if (узел && typeof window.ResizeObserver === 'function') new window.ResizeObserver(приСменеРазмера).observe(узел);
  }

