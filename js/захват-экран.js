  /** Позвать дверь сети по имени (слушатель стола или выход); нет такой двери — тишина. */
  function позватьДверьСети(имя, доводы) {
    const дверь = двериСети && двериСети[имя];
    return typeof дверь === 'function' ? дверь.apply(null, доводы || []) : undefined;
  }

  /**
   * Слушатели стола по режиму: в режиме «боты» — слушатели партии с ботами,
   * в режиме «сеть» — одноимённые двери сети. Чужой режим не слышит ничего.
   */
  function поРежиму(слушателиБотов) {
    const итог = {};
    ['приИзменении', 'приГотово', 'приИзменить', 'приВиде', 'приПротяжке', 'приПропуске', 'приДолгомКасанииСОстатком',
      'приСменеХолста', 'приКасанииКарты', 'приОтказе', 'приОткрытииЛиста'].forEach(имя => {
      итог[имя] = function () {
        if (режимСтола === 'сеть') return позватьДверьСети(имя, arguments);
        const свой = слушателиБотов[имя];
        return свой ? свой.apply(null, arguments) : undefined;
      };
    });
    return итог;
  }

  function достатьСтол() {
    if (стол) return стол;
    стол = window.ЗахватСтол.создать({
      документ: document,
      рисункиЕсть: false,   // пачки рисунков Кодекса ещё нет: шайбы, пилюли и значки скрыты
      слушатели: поРежиму({
        приИзменении: черновикИзменён,
        приГотово: человекГотов,
        приВиде: вид => { if (ход) { ход.вид = вид; нарисоватьКартуПоКадру(); } },
        // Стол шлёт { из, x, y } пока палец тянет приказ и null, когда отпустил или отменил: стрелку рисует карта-вид.
        приПротяжке: данные => {
          протяжкаПальцем = данные ? { откуда: данные.из, x: данные.x, y: данные.y } : null;
          нарисоватьКартуПоКадру();
        },
        приПропуске: пропуститьРаскрытие,
        приДолгомКасанииСОстатком: открытьПоставитьСюда,
        // Выбор, приказ или цель новичка поменялись — холст рисует «своё» заново (стол отдаёт его параметрыХолста).
        приСменеХолста: () => { if (ход) нарисоватьКартуПоКадру(); },
        приКасанииКарты: убратьИтогПриДействии,
        приОткрытииЛиста: закрытьСвоиЛистыПриЛистеСтола,
        приОтказе: () => { if (Звук && typeof Звук.отказ === 'function') Звук.отказ(); }
      })
    });
    // Стол слушает «Готово» сам; этот слушатель идёт вторым и видит, что стол спросил про остаток.
    $('захват-готово').addEventListener('click', спроситьОбОстатке);
    return стол;
  }

  /**
   * Сеть берёт стол: партия с ботами откладывается тем же путём, что уход в лобби (оставитьПартию).
   * Её окна закрываем: «Да, сдаться» в забытой плашке сдало бы уже сетевую партию,
   * а итог партии с ботами висел бы поверх сетевого стола.
   */
  function столДляСети(двери) {
    if (режимСтола === 'боты') {
      оставитьПартию();
      закрытьОкно('захват-итог');
      закрытьОкно('захват-сдаться-плашка');
      закрытьЖурнал();   // журнал ботов над сетевым столом показывал бы чужую партию
    }
    двериСети = двери || {};
    режимСтола = 'сеть';
    const столСети = достатьСтол();
    // Сеть сама считает место карты без отступа под пилюлю: стол не должен нести отступ ботов.
    if (столСети.задатьЗанятыйНиз(0)) занятыйНизКарты = 0;
    return столСети;
  }

  function отпуститьСтол() {
    // Итог сетевой партии над столом ботов не остаётся: его кнопки вели бы к ушедшей сети.
    if (итогСети) закрытьОкно('захват-итог');
    закрытьЖурнал();
    режимСтола = 'боты';
    двериСети = null;
    спрятатьСказать();
  }

