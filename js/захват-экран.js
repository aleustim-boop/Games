  function текстСовета() {
    if (!ход || !ход.выбор || !ход.выбор.новичок || ход.советСкрыт || ход.итог) return null;
    // Раунд, который сейчас играет человек (на раскрытии партия уже разобрана, поэтому свой счётчик).
    const раунд = ход.раундИгры;
    if (ход.раскрытие) return раунд === 1 ? СОВЕТЫ.раскрытие : null;
    if (раунд === 2 && ход.советИтог) return СОВЕТЫ.итог;
    if (раунд !== 1 || !ход.ждёмГотово) return null;
    const осталось = (ход.партия.подкрепление[КЛЮЧ_ЧЕЛОВЕКА] || 0) - поставлено(ход.черновик);
    if (осталось > 0) return СОВЕТЫ.поставить + осталось;
    return ход.черновик.приказы.length ? СОВЕТЫ.готово : СОВЕТЫ.удар;
  }

