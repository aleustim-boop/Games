  /**
   * Партия кончилась. Порядок жёсткий (ТЗ 5, 15.5): рекорд, очистка zahvat-save и билет —
   * ДО показа листа или окна: закрыть страницу в миг показа уже ничего не потеряет и не задвоит.
   */
  function партияОкончена(партия) {
    if (!ход || !партия || !партия.завершена || ход.итог) return;   // одна партия — один рекорд и одна сдача
    спрятатьПластину();   // итог прошлого раунда (сдача посреди партии) и подписи на конечной карте не нужны
    clearTimeout(таймерЧерновика);
    таймерЧерновика = null;
    снятьТаймерыРаскрытия();
    закрытьЛистОстатка();
    if (поставитьСюда) закрытьПоставитьСюда();
    ход.ждёмГотово = false;
    ход.раскрытие = false;
    ход.партия = партия;
    const итог = собратьИтог(партия);
    ход.итог = итог;
    освежитьСовет();
    записатьРекорд(итог);
    Память.очиститьСохранение();
    сдатьБилет(итог.вПлюсе);
    if (итог.вПлюсе) Звук.победа(); else Звук.поражение();
    показатьКонечнуюКарту(партия);
    показатьКонец(итог);
  }

  /** «Да, сдаться»: без сети человек один, поэтому сдача сразу кончает партию («все люди выбыли»). */
  function сдатьсяВПартии() {
    if (!ход || ход.итог) return;
    const ответ = Правила.сдаться(ход.партия, КЛЮЧ_ЧЕЛОВЕКА);
    if (!ответ.принято) return;
    if (ответ.завершена) { ЗахватЭкран.партияОкончена(копия(ход.партия)); return; }
    сохранить();
  }

  /* ----- «Досмотреть быстро» (ТЗ 5): только показ, итог уже записан ----- */

  /** Копия законченной партии, которую боты доигрывают сами: без полей конца и без правила «все люди выбыли». */
  function партияДляДосмотра(итог) {
    const партия = копия(итог.партия);
    ПОЛЯ_КОНЦА.forEach(поле => { delete партия[поле]; });
    партия.сЛюдьми = false;
    // Человек выбыл на шаге итогов уже разобранного раунда — правила не успели открыть следующий:
    // открываем его так же, как они (номер, подкрепление, пустые черновики). Сдача посреди раунда его не разбирала.
    if (ход.последний && ход.последний.раунд === партия.раунд) {
      партия.раунд += 1;
      партия.игроки.forEach(к => {
        партия.подкрепление[к] = Правила.подкрепление(партия, к).всего;
        партия.черновики[к] = Правила.пустойЧерновик();
      });
    }
    return партия;
  }

  function начатьДосмотр() {
    if (!ход || !ход.итог || ход.досмотр) return;
    $('захват-выбыл').classList.add('скрыт');
    отметитьЛистыЭкрана();
    const партия = партияДляДосмотра(ход.итог);
    if (партия.раунд > партия.всегоРаундов) { показатьИтог(ход.итог); return; }   // досматривать нечего
    Память.начатьДосмотр();
    ход.досмотр = true;
    ход.партия = партия;
    ход.наКарте = партия;
    спрятатьПластину();
    стол.задатьКонец(false);   // идёт досмотр: «конец» на строке раунда было бы неправдой
    стол.обновитьПартию(партия, { готовы: null });
    нарисоватьКарту();
    $('захват-досмотр').classList.remove('скрыт');
    таймерДосмотра = setTimeout(шагДосмотра, ДОСМОТР_РАУНД_МС);
  }

  /** Один раунд досмотра: черновики ботов, разбор правилами, новая карта на столе — без раскрытия. */
  function шагДосмотра() {
    таймерДосмотра = null;
    if (!ход || !ход.досмотр) return;
    const до = ход.партия;
    let разбор;
    try {
      const черновики = {};
      до.игроки.forEach(ключ => {
        if (Правила.вИгре(до, ключ)) черновики[ключ] = Правила.остатокПоПросрочке(до, ключ, черновикБота(до, ключ));
      });
      разбор = Правила.разобратьРаунд(копия(до), черновики, Math.random);
    } catch (ошибка) {
      console.warn('Захват: досмотр остановлен — раунд не разобрался', ошибка);
      досмотрКончился();
      return;
    }
    ход.партия = разбор.партия;
    ход.наКарте = разбор.партия;
    // Общий путь записи после разбора. Во время досмотра его глушит флажок памяти (ТЗ 5, 15.5):
    // иначе после перезагрузки появилось бы «Продолжить партию», а её конец записал бы второй рекорд.
    сохранить();
    стол.обновитьПартию(разбор.партия, { готовы: null });
    запертьПанель();
    нарисоватьКарту();
    if (разбор.партия.завершена) { стол.задатьКонец(true); запертьПанель(); досмотрКончился(); return; }
    таймерДосмотра = setTimeout(шагДосмотра, ДОСМОТР_РАУНД_МС);
  }

  /** Снять часы досмотра и его флажок (уход, новая партия, конец досмотра). */
  function остановитьДосмотр() {
    clearTimeout(таймерДосмотра);
    таймерДосмотра = null;
    if (ход) ход.досмотр = false;
    Память.закончитьДосмотр();
    $('захват-досмотр').classList.add('скрыт');
  }

  /** Досмотр кончился или его прервали кнопкой: показываем ЗАПИСАННЫЙ итог, не итог досмотра. */
  function досмотрКончился() {
    остановитьДосмотр();
    if (ход && ход.итог) показатьИтог(ход.итог);
  }

