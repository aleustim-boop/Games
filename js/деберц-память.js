'use strict';
/* Сохраняем начальное зерно и журнал действий: при чтении все ходы
 * заново проходят правила. Результат и партия записываются одним объектом,
 * поэтому перезагрузка экрана итога не создаёт повторную победу.
 */
(function () {
  const П = typeof module !== 'undefined' && module.exports ? require('./деберц-правила.js') : window.ДеберцПравила;
  const ключ = 'deberts_local_v1';
  const уровни = ['лёгкий', 'обычный', 'сложный'];
  function генератор(зерно) {
    return () => ((зерно = (Math.imul(зерно, 1664525) + 1013904223) >>> 0) / 4294967296);
  }
  function открыть(носитель) {
    let данные = { версия: 1, партия: null, результаты: [], настройки: { уровень: 'обычный', звук: true, цель: 301, режим: '2' } };
    let игра = null, случайно, ошибка = '';
    function применить(ход) {
      if (!ход || !Array.isArray(ход) || ход.length > 3) throw Error('Повреждён ход');
      if (ход[0] === 'торг') П.торг(игра, ход[1], ход[2]);
      else if (ход[0] === 'карта') П.сыграть(игра, ход[1], ход[2]);
      else if (ход[0] === 'взятка') П.забрать(игра);
      else if (ход[0] === 'раздача') П.раздать(игра, случайно);
      else if (ход[0] === 'правила6') { игра.версияПравил = 6; if (игра.следующийСдающий != null) игра.следующийСдающий = (игра.сдающий + 1) % игра.руки.length; }
      else if (ход[0] === 'сдача') {
        П.сдаться(игра, 0); игра.итог.описание = 'Вы сдались';
      } else throw Error('Неизвестный ход');
    }
    function сохранить() {
      try { носитель.setItem(ключ, JSON.stringify(данные)); ошибка = ''; }
      catch (_) { ошибка = 'Память недоступна. Партия сохранится только до закрытия страницы.'; }
    }
    try {
      const текст = носитель.getItem(ключ);
      if (текст && текст.length > 2000000) throw Error('Слишком большая запись');
      const запись = текст ? JSON.parse(текст) : null;
      if (запись) {
        if (запись.версия !== 1 || !Array.isArray(запись.результаты)) throw Error('Неверная версия');
        данные.результаты = запись.результаты.filter(р => р && typeof р.id === 'string' && р.id.length < 100
          && Number.isFinite(р.дата) && уровни.includes(р.уровень) && [0, 1, 2, 3].includes(р.победитель)
          && Array.isArray(р.счёт) && [2, 3, 4].includes(р.счёт.length) && р.счёт.every(n => Number.isInteger(n) && n >= 0)).slice(0, 30);
        if (уровни.includes(запись.настройки?.уровень)) данные.настройки.уровень = запись.настройки.уровень;
        if (typeof запись.настройки?.звук === 'boolean') данные.настройки.звук = запись.настройки.звук;
        if (П.цели.includes(запись.настройки?.цель)) данные.настройки.цель = запись.настройки.цель;
        if (Object.hasOwn(П.режимы, запись.настройки?.режим)) данные.настройки.режим = запись.настройки.режим;
        if (запись.партия) {
          const с = запись.партия;
          if (typeof с.id !== 'string' || с.id.length > 99 || !Number.isInteger(с.зерно) || с.зерно < 0 || с.зерно > 4294967295
            || !уровни.includes(с.уровень) || !Array.isArray(с.ходы) || с.ходы.length > 20000) throw Error('Повреждена партия');
          // Старые журналы доигрываются по прежним правилам, без внезапной
          // победы от комбинации, которая раньше считалась полтинником.
          случайно = генератор(с.зерно); игра = П.создать(случайно, с.цель ?? 301, с.правила >= 2, с.режим || '2', с.правила || 1);
          с.ходы.forEach(применить); данные.партия = с;
          if (игра.версияПравил >= 4 && игра.версияПравил < 6) { применить(['правила6']); с.ходы.push(['правила6']); сохранить(); }
        }
      }
    } catch (_) {
      игра = null; данные.партия = null;
      ошибка = 'Не удалось восстановить партию. Можно начать новую.';
    }
    function записатьИтог() {
      if (игра.фаза !== 'конец' || данные.результаты.some(р => р.id === данные.партия.id)) return;
      данные.результаты.unshift({ id: данные.партия.id, дата: Date.now(), уровень: данные.партия.уровень,
        победитель: игра.победитель, режим: игра.режим, цель: игра.цель, счёт: игра.счёт.slice(), сдач: игра.номер, сдался: !!игра.сдался });
      данные.результаты = данные.результаты.slice(0, 30);
    }
    return {
      get игра() { return игра; }, get ошибка() { return ошибка; },
      get уровень() { return данные.партия?.уровень || данные.настройки.уровень; },
      настройки: () => ({ ...данные.настройки }),
      результаты: () => данные.результаты.map(р => ({ ...р, счёт: р.счёт.slice() })),
      настроить(имя, значение) {
        if (имя === 'режим' && Object.hasOwn(П.режимы, значение)) данные.настройки.режим = значение;
        if (имя === 'цель' && П.цели.includes(значение)) данные.настройки.цель = значение;
        if (имя === 'уровень' && уровни.includes(значение)) данные.настройки.уровень = значение;
        if (имя === 'звук' && typeof значение === 'boolean') данные.настройки.звук = значение;
        сохранить();
      },
      новая(уровень = данные.настройки.уровень, цель = данные.настройки.цель, режим = данные.настройки.режим) {
        if (!уровни.includes(уровень)) throw Error('Неизвестный уровень');
        if (!П.цели.includes(цель)) throw Error('Неизвестная цель');
        if (!Object.hasOwn(П.режимы, режим)) throw Error('Неизвестный режим');
        const зерно = Math.floor(Math.random() * 4294967296);
        данные.партия = { id: Date.now().toString(36) + '-' + зерно.toString(36), зерно, уровень, цель, режим, правила: 6, ходы: [] };
        случайно = генератор(зерно); игра = П.создать(случайно, цель, true, режим); сохранить(); return игра;
      },
      ход(...ход) {
        if (!игра) throw Error('Нет партии');
        применить(ход); данные.партия.ходы.push(ход); записатьИтог(); сохранить(); return игра;
      }
    };
  }
  const модуль = { открыть, ключ, уровни };
  if (typeof module !== 'undefined' && module.exports) module.exports = модуль;
  if (typeof window !== 'undefined') window.ДеберцПамять = модуль;
})();
