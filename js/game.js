/**
 * Подвести серию побед после партии и записать результат.
 * Победа растит серию, проигрыш обнуляет, ничья не меняет ничего.
 */
function подвестиСерию(результат) {
  if (результат === 'бот') {            // дурак — бот, значит выиграл человек
    серияПобед++;
    запомнитьСерию();
    написатьВРамкуИтога('Побед подряд: ' + серияПобед + ' — записываем…');
    if (хранилищеРаботает()) {
      // Уровень берём у самой партии: в меню его могли переключить уже после
      // её начала, и тогда рекорд ушёл бы не с тем соперником.
      const уровеньПартии = партия ? партия.сложность : сложность;
      saveScore(серияПобед, уровеньПартии).then(function (рекорды) {
        const лучший = рекорды && рекорды.лучший ? рекорды.лучший : серияПобед;
        написатьВРамкуИтога(серияПобед >= лучший
          ? 'Побед подряд: ' + серияПобед + '. Это ваш рекорд!'
          : 'Побед подряд: ' + серияПобед + '. Лучшая серия: ' + лучший);
      });
    } else {
      написатьВРамкуИтога('Побед подряд: ' + серияПобед + ' (сохранить не удалось)');
    }
    return;
  }

  if (результат === 'человек') {        // дурак — человек, серия обрывается
    const была = серияПобед;
    серияПобед = 0;
    запомнитьСерию();
    написатьВРамкуИтога(была > 0
      ? 'Серия прервана: было ' + была + ' ' + словоПобед(была) + ' подряд'
      : 'Побед подряд: 0');
    return;
  }

  // ничья серию не трогает
  написатьВРамкуИтога('Ничья серию не прерывает. Побед подряд: ' + серияПобед);
}

