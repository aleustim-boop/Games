/* Рекорды хранит js/telegram.js (облако Telegram, а без него — память
   браузера). Здесь лежат только три мелочи самой игры: какой выбран
   соперник, включён ли звук и сколько побед подряд набрано сейчас.
   Они нужны мгновенно, ещё до ответа облака, поэтому лежат рядом. */
const КЛЮЧ_СЛОЖНОСТИ = 'подкидной-дурак:сложность';
const КЛЮЧ_ЗВУКА = 'подкидной-дурак:звук';
const КЛЮЧ_СЕРИИ = 'подкидной-дурак:серия';

/** Прочитать настройку. Памяти нет (или она запрещена) — вернём null, игра переживёт. */
function прочитатьНастройку(ключ) {
  try {
    return window.localStorage.getItem(ключ);
  } catch (ошибка) {
    return null;
  }
}

function записатьНастройку(ключ, значение) {
  try {
    window.localStorage.setItem(ключ, значение);
  } catch (ошибка) {
    /* запрещённая память — не повод ломать игру */
  }
}

let сложность = проверитьСложность(прочитатьНастройку(КЛЮЧ_СЛОЖНОСТИ));
let звукВключён = прочитатьНастройку(КЛЮЧ_ЗВУКА) !== 'выключен';
let серияПобед = Math.max(0, Number(прочитатьНастройку(КЛЮЧ_СЕРИИ)) || 0);

/** Слово «победа» после числа: 1 победа, 2 победы, 5 побед. */
function словоПобед(сколько) {
  const двеПоследние = сколько % 100;
  const последняя = сколько % 10;
  if (двеПоследние >= 11 && двеПоследние <= 14) return 'побед';
  if (последняя === 1) return 'победа';
  if (последняя >= 2 && последняя <= 4) return 'победы';
  return 'побед';
}

