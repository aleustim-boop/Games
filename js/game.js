/* Рекорды хранит js/telegram.js (облако Telegram, а без него — память
   браузера). Здесь лежат только три мелочи самой игры: какой выбран
   соперник, включён ли звук и сколько побед подряд набрано сейчас.
   Они нужны мгновенно, ещё до ответа облака, поэтому лежат рядом. */
const КЛЮЧ_СЛОЖНОСТИ = 'подкидной-дурак:сложность';
const КЛЮЧ_ЗВУКА = 'подкидной-дурак:звук';
const КЛЮЧ_СЕРИИ = 'подкидной-дурак:серия';

/** Прочитать настройку. Памяти нет (или она запрещена) — вернём null, игра переживёт. */
function прочитатьНастройку(ключ) {
  try {
    return window.localStorage.getItem(ключ);
  } catch (ошибка) {
    return null;
  }
}

function записатьНастройку(ключ, значение) {
  try {
    window.localStorage.setItem(ключ, значение);
  } catch (ошибка) {
    /* запрещённая память — не повод ломать игру */
  }
}

let сложность = проверитьСложность(прочитатьНастройку(КЛЮЧ_СЛОЖНОСТИ));
let звукВключён = прочитатьНастройку(КЛЮЧ_ЗВУКА) !== 'выключен';
let серияПобед = Math.max(0, Number(прочитатьНастройку(КЛЮЧ_СЕРИИ)) || 0);

/** Слово «победа» после числа: 1 победа, 2 победы, 5 побед. */
function словоПобед(сколько) {
  const двеПоследние = сколько % 100;
  const последняя = сколько % 10;
  if (двеПоследние >= 11 && двеПоследние <= 14) return 'побед';
  if (последняя === 1) return 'победа';
  if (последняя >= 2 && последняя <= 4) return 'победы';
  return 'побед';
}

/* ---------------------------------------------------------------------
   Выбор соперника
   --------------------------------------------------------------------- */

function выбратьСложность(новая) {
  сложность = проверитьСложность(новая);
  записатьНастройку(КЛЮЧ_СЛОЖНОСТИ, сложность);
  показатьВыбраннуюСложность();
}

/** Отметить в меню кнопку выбранного уровня. */
function показатьВыбраннуюСложность() {
  const блок = эл('выбор-сложности');
  if (!блок) return;
  for (const кнопка of блок.querySelectorAll('.кнопка--выбор')) {
    кнопка.classList.toggle('кнопка--активная', кнопка.value === сложность);
  }
  // Пишем выбор словами: так понятно, даже если нажатая кнопка ничем не выделена.
  написать('подпись-сложности', 'Соперник: ' + сложность);
}

function подключитьВыборСложности() {
  const блок = эл('выбор-сложности');
  if (!блок) {
    console.warn('Игра: не нашёл выбор сложности — играем обычным соперником.');
    return;
  }
  for (const кнопка of блок.querySelectorAll('.кнопка--выбор')) {
    кнопка.addEventListener('click', function () {
      выбратьСложность(кнопка.value);
      звукКарты();
    });
  }
}

/* ---------------------------------------------------------------------
   Звук. Файлов со звуками в проекте нет: короткие сигналы собираются
   прямо в браузере через Web Audio API.
   --------------------------------------------------------------------- */

const ГРОМКОСТЬ = 0.07;   // тихо: игра часто идёт в наушниках в транспорте
let звуковойДвижок = null;

/** Звуковой движок браузера. Создаём при первом звуке: до нажатия кнопки браузер его не даёт. */
function получитьЗвуковойДвижок() {
  if (звуковойДвижок) return звуковойДвижок;
  try {
    const Движок = window.AudioContext || window.webkitAudioContext;
    if (!Движок) return null;
    звуковойДвижок = new Движок();
  } catch (ошибка) {
    звуковойДвижок = null;
  }
  return звуковойДвижок;
}

/**
 * Один короткий сигнал: частота в герцах, длительность и задержка в секундах.
 * Нарастание и затухание нужны обязательно — без них слышен щелчок на краях.
 */
function сигнал(частота, длительность, задержка) {
  if (!звукВключён) return;
  const движок = получитьЗвуковойДвижок();
  if (!движок) return;
  try {
    if (движок.state === 'suspended') движок.resume();
    const начало = движок.currentTime + (задержка || 0);
    const генератор = движок.createOscillator();
    const громкость = движок.createGain();
    генератор.type = 'triangle';        // мягче синуса и без резкости квадрата
    генератор.frequency.setValueAtTime(частота, начало);
    громкость.gain.setValueAtTime(0.0001, начало);
    громкость.gain.exponentialRampToValueAtTime(ГРОМКОСТЬ, начало + 0.012);
    громкость.gain.exponentialRampToValueAtTime(0.0001, начало + длительность);
    генератор.connect(громкость);
    громкость.connect(движок.destination);
    генератор.start(начало);
    генератор.stop(начало + длительность + 0.02);
  } catch (ошибка) {
    /* звук — не то, ради чего стоит ронять игру */
  }
}

