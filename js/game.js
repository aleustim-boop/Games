/**
 * Узнать настоящий размер карты — тот, который получился в оформлении.
 * Своей формулы у игры больше нет: раньше она повторяла расчёт из style.css,
 * и стоило дизайнеру поменять там хоть одно число, как размеры расходились
 * и веер раскладывался с щелями. Теперь спрашиваем у браузера: ставим
 * невидимую карту, меряем её и по этому размеру раскладываем руку.
 */
function измеритьКарту() {
  const щуп = document.createElement('div');
  щуп.className = 'карта';
  щуп.style.position = 'absolute';
  щуп.style.left = '-9999px';
  щуп.style.visibility = 'hidden';
  document.body.appendChild(щуп);
  const место = щуп.getBoundingClientRect();
  document.body.removeChild(щуп);
  // Ноль означает, что оформление ещё не загрузилось: тогда оставляем прежние
  // значения, иначе рука схлопнется в точку.
  if (место.height > 0 && место.width > 0) {
    размерКарты.высота = место.height;
    размерКарты.ширина = место.width;
  }
}

/**
 * Сказать оформлению, какой ширины карта помещается в это окно: по ширине
 * экрана должно вставать шесть карт — столько их в руке при раздаче.
 * Насколько карта влезет по высоте и в какие пределы уложится, решает
 * style.css, а мы потом просто меряем, что получилось.
 */
function подобратьРазмерКарты() {
  const поШирине = Math.floor((window.innerWidth - 16) / 6) * ПРОПОРЦИЯ_КАРТЫ;
  document.documentElement.style.setProperty('--высота-карты', Math.round(поШирине) + 'px');
  измеритьКарту();
}

/** Собрать картинку одной карты. */
function элементКарты(карта, добавочныйКласс) {
  const узел = document.createElement('div');
  узел.className = 'карта';
  if (КРАСНЫЕ_МАСТИ.indexOf(карта.масть) !== -1) узел.classList.add('карта--красная');
  if (добавочныйКласс) узел.classList.add(добавочныйКласс);

  // Угол собираем из двух частей: достоинство и масть — отдельные элементы.
  // Так они всегда встают столбиком, а не зависят от переноса строки.
  const угол = document.createElement('div');
  угол.className = 'карта__угол';
  const номинал = document.createElement('span');
  номинал.className = 'карта__номинал';
  номинал.textContent = карта.имя;
  const мастьВУглу = document.createElement('span');
  мастьВУглу.className = 'карта__масть-угла';
  мастьВУглу.textContent = карта.масть;
  угол.appendChild(номинал);
  угол.appendChild(мастьВУглу);

  const масть = document.createElement('div');
  масть.className = 'карта__масть';
  масть.textContent = карта.масть;

  узел.appendChild(угол);
  узел.appendChild(масть);
  return узел;
}

/** Карта рубашкой вверх. */
function элементРубашки() {
  const узел = document.createElement('div');
  узел.className = 'карта карта--рубашка';
  return узел;
}

/**
 * Шаг между картами в ряду. Он же — ширина полоски, которая остаётся видна
 * от каждой карты: именно по ней игрок целится пальцем.
 */
function шагВРяду(ширинаКарты, картВРяду, доступно) {
  if (картВРяду <= 1) return 0;
  return Math.min(ширинаКарты + ЗАЗОР_КАРТ, (доступно - ширинаКарты) / (картВРяду - 1));
}

/**
 * Разложить карты веером внахлёст: считаем шаг так, чтобы любое
 * количество карт уместилось в ширину экрана.
 */
function разложитьВеером(контейнер, отступСверху) {
  const карты = контейнер.children;
  if (карты.length === 0) return;
  const доступно = контейнер.clientWidth || window.innerWidth;
  const шаг = шагВРяду(размерКарты.ширина, карты.length, доступно);
  const занято = размерКарты.ширина + шаг * (карты.length - 1);
  const старт = Math.max(0, (доступно - занято) / 2);
  for (let i = 0; i < карты.length; i++) {
    карты[i].style.left = Math.round(старт + шаг * i) + 'px';
    карты[i].style.top = отступСверху + 'px';
  }
}

function рисоватьРукуБота() {
  const веер = эл('карты-бота');
  if (!веер) return;
  веер.innerHTML = '';
  for (let i = 0; i < партия.руки.бот.length; i++) {
    веер.appendChild(элементРубашки());
  }
  разложитьВеером(веер, 2);
  // Пишем и уровень: иначе после «Играть ещё» непонятно, с кем сейчас играешь.
  // В игре вдвоём уровня нет вовсе — там за столом живой человек.
  const сколько = партия.руки.бот.length;
  const кто = этоСетеваяИгра()
    ? 'Друг'
    : партия.сложность.charAt(0).toUpperCase() + партия.сложность.slice(1) + ' соперник';
  написать('счётчик-бота', кто + ': ' + сколько + ' ' + словоКарты(сколько));
}

function рисоватьКолоду() {
  const козырь = эл('козырная-карта');
  const верх = эл('верх-колоды');
  const счётчик = эл('счётчик-колоды');
  if (козырь) козырь.innerHTML = '';
  if (верх) верх.innerHTML = '';

  // Козырная карта видна, пока она ещё в колоде; рубашка — пока над ней есть карты.
  if (козырь && партия.колода.length > 0) козырь.appendChild(элементКарты(партия.козырнаяКарта));
  if (верх && партия.колода.length > 1) верх.appendChild(элементРубашки());

  // Подписываем счётчик и не прячем его: когда колода кончилась,
  // важно прямо сказать об этом, а не убирать угол с экрана.
  const осталось = партия.колода.length;
  if (счётчик) {
    счётчик.textContent = осталось > 0
      ? 'В колоде ' + осталось + ' ' + словоКарты(осталось)
      : 'Колода пуста';
    счётчик.classList.remove('скрыт');
  }
  написать('метка-козыря', 'Козырь ' + партия.козырь);
}

function рисоватьСтол() {
  const стол = эл('стол');
  if (!стол) return;
  стол.innerHTML = '';
  const человекЗащищается = защищается(партия) === 'человек' && фаза(партия) === 'защита';
  const поднятая = выбраннаяКарта !== null ? партия.руки.человек[выбраннаяКарта] : null;

  партия.стол.forEach(function (пара, индекс) {
    const узел = document.createElement('div');
    узел.className = 'пара';
    узел.appendChild(элементКарты(пара.атака, 'карта--атака'));
    if (пара.защита) узел.appendChild(элементКарты(пара.защита, 'карта--защита'));

    // Подсвечиваем те карты, которые человек может побить выбранной картой.
    if (человекЗащищается && поднятая && !пара.защита &&
        бьёт(поднятая, пара.атака, партия.козырь)) {
      узел.classList.add('пара--цель');
    }
    узел.addEventListener('click', function () { тапПоПаре(индекс); });
    стол.appendChild(узел);
  });
}

/* Когда рука раскладывается в два ряда.
   Раньше порогом было 20 карт и ряд не ниже 40 точек — из-за этого на
   невысоком экране два ряда не включались никогда, а перед самым порогом
   получался провал: 19 карт — полоска 17 точек, 20 карт — сразу 30.
   Теперь порог низкий, ряд может быть мелким, а решает сравнение: два ряда
   берём, только если видимая полоска карты станет заметно шире. Мелкая
   карта хуже читается, но подпись оформление уменьшает ступенями, а вот
   попасть пальцем в полоску шириной 6 точек нельзя вовсе. */
const ПОРОГ_ДВУХ_РЯДОВ = 12;
const МИН_ВЫСОТА_В_РЯДУ = 24;
const ВЫГОДА_ДВУХ_РЯДОВ = 1.15;   // насколько шире должна стать полоска
const ЗАЗОР_КАРТ = 4;             // просвет между картами, пока рука не тесная
const ОТСТУП_РУКИ = 14;    // запас сверху: выбранная карта приподнимается
/* На сколько поднимается выбранная карта, когда рука лежит в два ряда.
   Это своя величина, с зазором между рядами она не связана.
   Больше 14 брать нельзя: столько запаса оставлено сверху полоски руки,
   и карта верхнего ряда полезла бы на строку подсказки. Снизу подъём
   закрывает у верхних карт только нижние 8 точек — номинал с мастью
   сидят в верхнем углу и остаются видны. */
const ПОДЪЁМ_В_ДВА_РЯДА = 14;
// Зазор между рядами. При двух точках щель тоньше рамки карты, и ряды
// сливаются в сплошную сетку. Больше шести брать нельзя: на телефоне
// шириной 360 точек ряд становится ниже порога и рука схлопывается в один.
const ЗАЗОР_РЯДОВ = 6;

/**
 * Нужны ли два ряда и какой высоты будут в них карты. Возвращает 0, если
 * рука остаётся в один ряд: карт мало, высоты не хватает или два ряда
 * ничего не выигрывают.
 */
function высотаРядаДляДвух(картВРуке, доступно) {
  if (картВРуке < ПОРОГ_ДВУХ_РЯДОВ) return 0;

  const рука = эл('карты-человека');
  // Высоту полоски берём из вёрстки, а не считаем заново.
  const полоска = рука && рука.clientHeight > 0 ? рука.clientHeight : размерКарты.высота + 18;
  const высотаРяда = Math.floor((полоска - ОТСТУП_РУКИ - ЗАЗОР_РЯДОВ) / 2);
  if (высотаРяда < МИН_ВЫСОТА_В_РЯДУ) return 0;

  // Считаем оба варианта и сравниваем то, ради чего всё затевалось, —
  // ширину полоски, в которую надо попасть пальцем.
  const вОдинРяд = шагВРяду(размерКарты.ширина, картВРуке, доступно);
  const вДваРяда = шагВРяду(размерКарты.ширина, Math.ceil(картВРуке / 2), доступно);
  return вДваРяда > вОдинРяд * ВЫГОДА_ДВУХ_РЯДОВ ? высотаРяда : 0;
}

/**
 * Разложить руку в два ряда. В одном ряду 35 карт превращаются в полоски
 * по 9 точек, и палец попадает в соседнюю; в двух рядах карт вдвое меньше,
 * и каждая шире.
 */
function разложитьДвумяРядами(контейнер, высотаРяда) {
  const карты = контейнер.children;
  if (карты.length === 0) return;
  const ширинаКарты = размерКарты.ширина;   // по ширине карта не ужимается
  const доступно = контейнер.clientWidth || window.innerWidth;
  const вВерхнем = Math.ceil(карты.length / 2);

  for (let i = 0; i < карты.length; i++) {
    const верхний = i < вВерхнем;
    const вРяду = верхний ? вВерхнем : карты.length - вВерхнем;
    const номерВРяду = верхний ? i : i - вВерхнем;
    const шаг = шагВРяду(ширинаКарты, вРяду, доступно);
    const занято = ширинаКарты + шаг * (вРяду - 1);
    const старт = Math.max(0, (доступно - занято) / 2);
    карты[i].style.left = Math.round(старт + шаг * номерВРяду) + 'px';
    карты[i].style.top = (верхний ? ОТСТУП_РУКИ : ОТСТУП_РУКИ + высотаРяда + ЗАЗОР_РЯДОВ) + 'px';
  }
}

/**
 * Можно ли сейчас сходить этой картой. Игра это и так знает — иначе не умела бы
 * отказывать; показываем знание игроку, чтобы он не считал в уме.
 * Не наш ход — возвращаем null: тогда карты остаются обычными, без пометок.
 */
function картаСейчасХодит(карта) {
  const текущая = фаза(партия);
  if (ктоХодит(партия) !== 'человек') return null;
  if (текущая === 'защита') {
    for (const пара of партия.стол) {
      if (!пара.защита && бьёт(карта, пара.атака, партия.козырь)) return true;
    }
    return false;
  }
  if (текущая === 'атака' || текущая === 'подкидывание' || текущая === 'докидывание') {
    return можноПоложить(партия, карта);
  }
  return null;
}

/**
 * Отказ по карте: пометка под пальцем плюс объяснение в подсказке.
 * Руку целиком не перерисовываем — иначе пометка отказа тут же исчезнет.
 */
function отказатьПоКарте(индекс, текст) {
  показатьСобытие(текст);
  рисоватьПодсказкуИКнопки();
  const веер = эл('карты-человека');
  const узел = веер ? веер.children[индекс] : null;
  if (!узел) return;
  узел.classList.remove('карта--отказ');
  // Пауза в один кадр нужна, чтобы пометка сработала и на повторный тап
  // по той же карте: без неё браузер не заметит, что класс возвращали.
  requestAnimationFrame(function () {
    узел.classList.add('карта--отказ');
  });
  setTimeout(function () { узел.classList.remove('карта--отказ'); }, ПОКАЗ_ОТКАЗА);
}

function рисоватьРукуЧеловека() {
  const веер = эл('карты-человека');
  if (!веер) return;
  веер.innerHTML = '';

  const доступно = веер.clientWidth || window.innerWidth;
  const высотаРяда = высотаРядаДляДвух(партия.руки.человек.length, доступно);

  партия.руки.человек.forEach(function (карта, индекс) {
    const узел = элементКарты(карта);
    // Подсказка глазами: чем можно ходить прямо сейчас, а чем нельзя.
    const ходит = картаСейчасХодит(карта);
    if (ходит === true) узел.classList.add('карта--можно');
    else if (ходит === false) узел.classList.add('карта--нельзя');
    if (высотаРяда) {
      // Ужимаем карту только по высоте: её не хватает на два ряда. Ширину
      // не трогаем — от неё оформление считает кегль подписи, а ужатая
      // пропорционально карта на невысоком экране выходит шириной в 21
      // точку, и номинал на ней уже не прочесть.
      узел.style.setProperty('--в', высотаРяда + 'px');
    }
    if (индекс === выбраннаяКарта) {
      узел.classList.add('карта--выбрана');
      // Подъём в два ряда не привязан к зазору — это своя величина.
      if (высотаРяда) узел.style.transform = 'translateY(-' + ПОДЪЁМ_В_ДВА_РЯДА + 'px)';
    }
    узел.addEventListener('click', function () { тапПоКартеЧеловека(индекс); });
    веер.appendChild(узел);
  });

  if (высотаРяда) разложитьДвумяРядами(веер, высотаРяда);
  else разложитьВеером(веер, ОТСТУП_РУКИ);
}

/** Есть ли у человека хоть одна карта, которую сейчас разрешено подкинуть. */
function естьЧемПодкинуть() {
  for (const карта of партия.руки.человек) {
    if (можноПоложить(партия, карта)) return true;
  }
  return false;
}

/** Есть ли чем крыть хоть одну карту на столе. */
function естьЧемОтбиться() {
  for (const пара of партия.стол) {
    if (пара.защита) continue;
    for (const карта of партия.руки.человек) {
      if (бьёт(карта, пара.атака, партия.козырь)) return true;
    }
  }
  return false;
}

/** Что от человека ждут прямо сейчас. Эта строка видна всегда. */
function текстДействия() {
  const текущая = фаза(партия);
  const ходит = ктоХодит(партия);
  const человекАтакует = партия.атакует === 'человек';

  if (текущая === 'атака') {
    return человекАтакует ? 'Ваш ход — выберите карту' : 'Соперник ходит…';
  }
  if (текущая === 'защита') {
    if (ходит !== 'человек') return 'Соперник отбивается…';
    if (выбраннаяКарта !== null) return 'Укажите карту на столе, которую бьёте';
    // Не зовём выбирать карту, если крыть нечем: игра это знает заранее.
    return естьЧемОтбиться()
      ? 'Отбивайтесь — выберите карту'
      : 'Отбиться нечем — жмите «Беру»';
  }
  if (текущая === 'подкидывание') {
    if (!человекАтакует) return 'Соперник думает, что подкинуть…';
    return естьЧемПодкинуть()
      ? 'Можете подкинуть или нажать «Бито»'
      : 'Подкинуть нечем — нажмите «Бито»';
  }
  if (текущая === 'докидывание') {
    if (!человекАтакует) return 'Вы забираете карты. Соперник может подкинуть…';
    // Тексты нарочно короткие: вместе с рассказом о событии они должны
    // умещаться в две строки подсказки (около 90 знаков на двоих).
    return естьЧемПодкинуть()
      ? 'Соперник берёт — можно подкинуть или «Готово»'
      : 'Соперник берёт — подкинуть нечем, жмите «Готово»';
  }
  // Партия доиграна: между последним ходом и экраном итога строка не пустует.
  return 'Партия окончена';
}

/** Строка подсказки и кнопки хода. */
function рисоватьПодсказкуИКнопки() {
  const текущая = фаза(партия);
  const ходит = ктоХодит(партия);
  const человекАтакует = партия.атакует === 'человек';
  const действие = текстДействия();

  // Сначала рассказ о событии, через точку — напоминание, что делать.
  const подсказка = эл('подсказка');
  if (подсказка) {
    подсказка.textContent = событие
      ? (действие ? событие + ' · ' + действие : событие)
      : действие;
    подсказка.classList.toggle('подсказка--событие', Boolean(событие));
    // Отдельная пометка «сейчас ходите вы» — её оформление задаёт style.css.
    подсказка.classList.toggle('подсказка--ваш-ход', ходит === 'человек');
  }

  const можноБито = человекАтакует && (текущая === 'подкидывание' || текущая === 'докидывание');
  const можноБеру = текущая === 'защита' && ходит === 'человек';
  // Когда соперник берёт, ничего не «бито» — карты уходят ему, поэтому другая надпись.
  написать('кнопка-завершить', текущая === 'докидывание' ? 'Готово' : 'Бито');
  показатьЭлемент('кнопка-завершить', можноБито);
  показатьЭлемент('кнопка-беру', можноБеру);
}

/** Единственная точка отрисовки: экран целиком собирается заново по состоянию. */
function перерисовать() {
  if (!партия) return;
  рисоватьРукуБота();
  рисоватьКолоду();
  рисоватьСтол();
  рисоватьРукуЧеловека();
  рисоватьПодсказкуИКнопки();
}

/* ---------------------------------------------------------------------
   Ход игры: после каждого действия перерисовываем экран и,
   если очередь бота, ставим его ход на таймер.
   --------------------------------------------------------------------- */

/** Снимок стола перед чужим ходом — по нему потом поймём, что именно случилось. */
function снимокДляРассказа() {
  return {
    парНаСтоле: партия.стол.length,
    отбитые: партия.стол.map(function (пара) { return Boolean(пара.защита); }),
    картНаСтоле: количествоКартНаСтоле(),
    берёт: партия.берёт,
    защитник: защищается(партия)
  };
}

/** Сколько карт сейчас лежит на столе — вместе с теми, которыми отбились. */
function количествоКартНаСтоле() {
  let счёт = 0;
  for (const пара of партия.стол) {
    счёт++;
    if (пара.защита) счёт++;
  }
  return счёт;
}

/**
 * Чем кончился подход. Считать нужно ДО завершения подхода:
 * после него стол уже пуст и сказать нечего.
 */
function текстКонцаПодхода(картНаСтоле, берёт, защитник) {
  if (берёт) {
    const слово = словоКарты(картНаСтоле, true);
    return защитник === 'человек'
      ? 'Вы забрали ' + картНаСтоле + ' ' + слово
      : 'Соперник забрал ' + картНаСтоле + ' ' + слово;
  }
  return 'Бито — в отбой ' + картНаСтоле + ' ' + словоКарты(картНаСтоле);
}

/** Что сделал бот: сравниваем стол до хода и после. */
function рассказатьОХодеБота(было) {
  // Подход закончился: стол опустел.
  if (было.парНаСтоле > 0 && партия.стол.length === 0) {
    if (было.берёт) return текстКонцаПодхода(было.картНаСтоле, true, было.защитник);
    return 'Соперник сказал «Бито» — в отбой ' + было.картНаСтоле +
           ' ' + словоКарты(было.картНаСтоле);
  }
  // Бот положил карту.
  if (партия.стол.length > было.парНаСтоле) {
    const карта = названиеКарты(партия.стол[партия.стол.length - 1].атака);
    if (было.парНаСтоле === 0) return 'Соперник ходит ' + карта;
    return 'Соперник подкинул ' + карта;
  }
  // Бот решил взять.
  if (!было.берёт && партия.берёт) return 'Соперник не смог отбиться';
  // Бот отбился: ищем пару, у которой появилась защита.
  for (let i = 0; i < партия.стол.length; i++) {
    if (партия.стол[i].защита && !было.отбитые[i]) {
      return 'Соперник отбил ' + названиеКарты(партия.стол[i].атака) +
             ' картой ' + названиеКарты(партия.стол[i].защита);
    }
  }
  return '';
}

/** Звук под ход бота: карты по столу шуршат иначе, чем забранная охапка. */
function озвучитьХодБота(было) {
  const подходЗакончился = было.парНаСтоле > 0 && партия.стол.length === 0;
  if (подходЗакончился) {
    if (было.берёт) звукВзятия(); else звукКарты();
    return;
  }
  if (партия.стол.length > было.парНаСтоле) { звукКарты(); return; }   // положил карту
  if (!было.берёт && партия.берёт) { звукВзятия(); return; }          // решил взять
  for (let i = 0; i < партия.стол.length; i++) {
    if (партия.стол[i].защита && !было.отбитые[i]) { звукКарты(); return; }  // отбился
  }
}

/** Ход бота на экране: сходил — рассказали, что сделал. */
function сделатьХодБота() {
  таймер = null;
  // Партии может уже не быть: игрок вышел в меню, пока ход был отложен.
  if (!партия || партия.завершена) return;
  const было = снимокДляРассказа();
  ходБота(партия, 'бот');
  const рассказ = рассказатьОХодеБота(было);
  if (рассказ) показатьСобытие(рассказ);
  озвучитьХодБота(было);
  продолжить();
}

function продолжить() {
  // Страховка для игры вдвоём: там ходы приходят с сервера, а бот не играет
  // вовсе. Проверка стоит в самой развилке — так ни один забытый путь
  // не сможет случайно разбудить робота посреди партии с живым другом.
  if (этоСетеваяИгра()) {
    перерисовать();
    return;
  }
  перерисовать();
  if (партия.завершена) {
    // Итог засчитываем прямо сейчас, а плашку показываем чуть позже.
    // Раньше и то и другое ждало показа: игрок успевал выйти в меню
    // за эти две секунды, и проигрыш просто не записывался.
    засчитатьИтог();
    отменитьПоказИтога();
    таймерИтога = setTimeout(показатьРезультат, Math.max(900, ждатьПодСобытие() + 500));
    return;
  }
  if (ктоХодит(партия) === 'бот') {
    // Бот не спешит: пока висит сообщение о прошлом событии, он ждёт.
    таймер = setTimeout(сделатьХодБота, Math.max(ЗАДЕРЖКА_БОТА, ждатьПодСобытие()));
  }
}

/**
 * Партия кончилась: записываем результат и звучим об этом.
 * Делается ровно один раз и сразу — до всяких показов и задержек,
 * чтобы выход в меню уже ничего не отменял.
 */
function засчитатьИтог() {
  if (итогЗасчитан || !партия) return;
  итогЗасчитан = true;
  if (партия.результат === 'бот') звукПобеды();
  else if (партия.результат === 'человек') звукПроигрыша();
  подвестиСерию(партия.результат);
}

/**
 * Заголовок итога и объяснение под ним: чем кончилась партия.
 * Вынесено отдельно, потому что в игре вдвоём эти надписи приходится
 * освежать и после показа плашки — друг может выйти из-за стола или
 * позвать на реванш уже тогда, когда итог на экране.
 */
function текстыИтога() {
  if (!партия) return { заголовок: '', пояснение: '' };
  if (партия.результат === 'бот') {
    return {
      заголовок: 'Вы выиграли!',
      пояснение: 'Соперник остался с картами — он и есть дурак.'
    };
  }
  if (партия.результат === 'человек') {
    return {
      заголовок: 'Вы проиграли',
      пояснение: 'Вы остались с картами — на этот раз дурак вы.'
    };
  }
  if (партия.результат === 'друг-ушёл') {
    // Никого не обвиняем: чаще всего у друга просто пропала связь.
    return {
      заголовок: 'Друг вышел из игры',
      пояснение: 'Партия прервалась на середине — возможно, у друга пропала связь. ' +
                 'Дурака в такой партии нет.'
    };
  }
  if (партия.результат === 'связь-потеряна') {
    // Человек не виноват: у него пропал интернет, и партия закрылась без него.
    return {
      заголовок: 'Партия прервалась',
      пояснение: 'Связь пропадала слишком долго, и игра закончилась без вас. ' +
                 'Дурака в такой партии нет — вернитесь в меню и начните новую игру.'
    };
  }
  return { заголовок: 'Ничья', пояснение: 'Карты кончились у обоих — дурака нет.' };
}

/**
 * Написать заголовок итога и подпись под ним. В игре вдвоём к подписи
 * добавляется вторая фраза — что делать дальше. Такие объяснения занимают
 * две-три строки, и в рамку для короткой строки «Побед подряд: 3» им нельзя:
 * там они кричат громче самого заголовка.
 */
function обновитьТекстыИтога() {
  const тексты = текстыИтога();
  const хвост = этоСетеваяИгра() && подсказкаПослеПартии ? ' ' + подсказкаПослеПартии : '';
  написать('текст-результата', тексты.заголовок);
  написать('пояснение-результата', тексты.пояснение + хвост);
}

function показатьРезультат() {
  таймерИтога = null;
  // За паузу перед показом всё могло измениться, поэтому проверяем заново:
  // партия есть, она действительно доиграна, человек стоит у стола и не занят
  // вопросом «точно выйти?». Иначе плашка легла бы поверх чужого экрана
  // и перекрыла бы кнопки.
  if (!партия || !партия.завершена) return;
  if (!этоЭкранИгры() || ждёмОтветПроВыход) return;
  обновитьТекстыИтога();
  // В игре вдвоём эта же кнопка предлагает не новую партию с ботом,
  // а реванш в той же комнате — с тем же другом и тем же кодом.
  написать('кнопка-ещё', этоСетеваяИгра() ? 'Ещё партию' : 'Играть ещё');
  показатьЭлемент('кнопка-ещё', реваншВозможен());
  показатьПлашкуИтога();
}

