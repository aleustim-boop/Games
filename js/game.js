const ЗАДЕРЖКА_БОТА = 700;      // пауза перед ходом бота, чтобы ход было видно
const ПРОПОРЦИЯ_КАРТЫ = 1.45;   // высота карты относительно ширины

let партия = null;
let выбраннаяКарта = null;      // индекс карты в руке человека, поднятой для защиты
let подсказкаОдинРаз = null;    // короткое сообщение, показывается до следующей перерисовки
let таймер = null;              // отложенный ход бота или показ результата
const размерКарты = { ширина: 48, высота: 70 };

function эл(id) {
  return document.getElementById(id);
}

/** Показать один из трёх экранов, остальные спрятать. */
function показатьЭкран(id) {
  for (const экран of document.querySelectorAll('.экран')) {
    экран.classList.toggle('экран--виден', экран.id === id);
  }
}

/**
 * Подобрать размер карты под окно: по ширине должно помещаться около
 * семи карт, по высоте — две руки и стол в два ряда.
 */
function подобратьРазмерКарты() {
  const поШирине = Math.floor((window.innerWidth - 16) / 7) * ПРОПОРЦИЯ_КАРТЫ;
  const поВысоте = (window.innerHeight - 140) / 3.3;
  const высота = Math.max(54, Math.min(104, Math.floor(Math.min(поШирине, поВысоте))));
  размерКарты.высота = высота;
  размерКарты.ширина = Math.round(высота / ПРОПОРЦИЯ_КАРТЫ);
  const корень = document.documentElement.style;
  корень.setProperty('--высота-карты', размерКарты.высота + 'px');
  корень.setProperty('--ширина-карты', размерКарты.ширина + 'px');
  // В разметке высота строки с картами человека не задана, а карты лежат
  // «поверх» неё, поэтому высоту задаём отсюда (+ запас на поднятую карту).
  эл('рука-человека').style.height = (размерКарты.высота + 18) + 'px';
}

/** Собрать картинку одной карты. */
function элементКарты(карта, добавочныйКласс) {
  const узел = document.createElement('div');
  узел.className = 'карта';
  if (КРАСНЫЕ_МАСТИ.indexOf(карта.масть) !== -1) узел.classList.add('карта--красная');
  if (добавочныйКласс) узел.classList.add(добавочныйКласс);

  const угол = document.createElement('div');
  угол.className = 'карта__угол';
  угол.textContent = карта.имя + карта.масть;

  const масть = document.createElement('div');
  масть.className = 'карта__масть';
  масть.textContent = карта.масть;

  узел.appendChild(угол);
  узел.appendChild(масть);
  return узел;
}

/** Карта рубашкой вверх. */
function элементРубашки() {
  const узел = document.createElement('div');
  узел.className = 'карта карта--рубашка';
  return узел;
}

/**
 * Разложить карты веером внахлёст: считаем шаг так, чтобы любое
 * количество карт уместилось в ширину экрана.
 */
function разложитьВеером(контейнер, отступСверху) {
  const карты = контейнер.children;
  if (карты.length === 0) return;
  const доступно = контейнер.clientWidth || window.innerWidth;
  const шаг = карты.length > 1
    ? Math.min(размерКарты.ширина + 4, (доступно - размерКарты.ширина) / (карты.length - 1))
    : 0;
  const занято = размерКарты.ширина + шаг * (карты.length - 1);
  const старт = Math.max(0, (доступно - занято) / 2);
  for (let i = 0; i < карты.length; i++) {
    карты[i].style.left = Math.round(старт + шаг * i) + 'px';
    карты[i].style.top = отступСверху + 'px';
  }
}

function рисоватьРукуБота() {
  const веер = эл('карты-бота');
  веер.innerHTML = '';
  for (let i = 0; i < партия.руки.бот.length; i++) {
    веер.appendChild(элементРубашки());
  }
  разложитьВеером(веер, 2);
  эл('счётчик-бота').textContent = String(партия.руки.бот.length);
}

function рисоватьКолоду() {
  const козырь = эл('козырная-карта');
  const верх = эл('верх-колоды');
  const счётчик = эл('счётчик-колоды');
  козырь.innerHTML = '';
  верх.innerHTML = '';

  // Козырная карта видна, пока она ещё в колоде; рубашка — пока над ней есть карты.
  if (партия.колода.length > 0) козырь.appendChild(элементКарты(партия.козырнаяКарта));
  if (партия.колода.length > 1) верх.appendChild(элементРубашки());

  счётчик.textContent = String(партия.колода.length);
  счётчик.classList.toggle('скрыт', партия.колода.length === 0);
  эл('метка-козыря').textContent = 'Козырь ' + партия.козырь;
}

function рисоватьСтол() {
  const стол = эл('стол');
  стол.innerHTML = '';
  const человекЗащищается = защищается(партия) === 'человек' && фаза(партия) === 'защита';
  const поднятая = выбраннаяКарта !== null ? партия.руки.человек[выбраннаяКарта] : null;

  партия.стол.forEach(function (пара, индекс) {
    const узел = document.createElement('div');
    узел.className = 'пара';
    узел.appendChild(элементКарты(пара.атака, 'карта--атака'));
    if (пара.защита) узел.appendChild(элементКарты(пара.защита, 'карта--защита'));

    // Подсвечиваем те карты, которые человек может побить выбранной картой.
    if (человекЗащищается && поднятая && !пара.защита &&
        бьёт(поднятая, пара.атака, партия.козырь)) {
      узел.classList.add('пара--цель');
    }
    узел.addEventListener('click', function () { тапПоПаре(индекс); });
    стол.appendChild(узел);
  });
}

function рисоватьРукуЧеловека() {
  const веер = эл('карты-человека');
  веер.innerHTML = '';
  партия.руки.человек.forEach(function (карта, индекс) {
    const узел = элементКарты(карта);
    if (индекс === выбраннаяКарта) узел.classList.add('карта--выбрана');
    узел.addEventListener('click', function () { тапПоКартеЧеловека(индекс); });
    веер.appendChild(узел);
  });
  // Отступ сверху с запасом: выбранная карта приподнимается на 14 пикселей.
  разложитьВеером(веер, 14);
}

/** Строка подсказки и две кнопки хода — что от человека ждут прямо сейчас. */
function рисоватьПодсказкуИКнопки() {
  const текущая = фаза(партия);
  const ходит = ктоХодит(партия);
  const человекАтакует = партия.атакует === 'человек';
  let текст = '';

  if (текущая === 'атака') {
    текст = человекАтакует ? 'Ваш ход — выберите карту' : 'Соперник ходит…';
  } else if (текущая === 'защита') {
    if (ходит === 'человек') {
      текст = выбраннаяКарта === null
        ? 'Отбивайтесь — выберите карту'
        : 'Теперь укажите карту на столе, которую бьёте';
    } else {
      текст = 'Соперник отбивается…';
    }
  } else if (текущая === 'подкидывание') {
    текст = человекАтакует
      ? 'Можете подкинуть или нажать «Бито»'
      : 'Соперник думает, что подкинуть…';
  } else if (текущая === 'докидывание') {
    текст = человекАтакует
      ? 'Соперник берёт. Можете подкинуть или нажать «Бито»'
      : 'Вы забираете карты. Соперник может подкинуть…';
  }

  // Разовое сообщение (например, «этой картой нельзя») важнее обычной подсказки.
  if (подсказкаОдинРаз) {
    текст = подсказкаОдинРаз;
    подсказкаОдинРаз = null;
  }
  эл('подсказка').textContent = текст;

  const можноБито = человекАтакует && (текущая === 'подкидывание' || текущая === 'докидывание');
  const можноБеру = текущая === 'защита' && ходит === 'человек';
  эл('кнопка-завершить').classList.toggle('скрыт', !можноБито);
  эл('кнопка-беру').classList.toggle('скрыт', !можноБеру);
}

/** Единственная точка отрисовки: экран целиком собирается заново по состоянию. */
function перерисовать() {
  if (!партия) return;
  рисоватьРукуБота();
  рисоватьКолоду();
  рисоватьСтол();
  рисоватьРукуЧеловека();
  рисоватьПодсказкуИКнопки();
}

/* ---------------------------------------------------------------------
   Ход игры: после каждого действия перерисовываем экран и,
   если очередь бота, ставим его ход на таймер.
   --------------------------------------------------------------------- */

function продолжить() {
  перерисовать();
  if (партия.завершена) {
    таймер = setTimeout(показатьРезультат, 900);
    return;
  }
  if (ктоХодит(партия) === 'бот') {
    таймер = setTimeout(function () {
      таймер = null;
      ходБота(партия, 'бот');
      продолжить();
    }, ЗАДЕРЖКА_БОТА);
  }
}

function показатьРезультат() {
  таймер = null;
  let заголовок = 'Ничья';
  let пояснение = 'Карты кончились у обоих — дурака нет.';
  if (партия.результат === 'бот') {
    заголовок = 'Вы выиграли!';
    пояснение = 'Соперник остался с картами — он и есть дурак.';
  } else if (партия.результат === 'человек') {
    заголовок = 'Вы проиграли';
    пояснение = 'Вы остались с картами — на этот раз дурак вы.';
  }
  эл('текст-результата').textContent = заголовок;
  эл('пояснение-результата').textContent = пояснение;
  показатьЭкран('экран-результата');
}

/* ---------------------------------------------------------------------
   Действия человека
   --------------------------------------------------------------------- */

function тапПоКартеЧеловека(индекс) {
  if (!партия || партия.завершена) return;
  if (ктоХодит(партия) !== 'человек') return;
  const карта = партия.руки.человек[индекс];
  if (!карта) return;
  const текущая = фаза(партия);

  if (текущая === 'атака' || текущая === 'подкидывание' || текущая === 'докидывание') {
    if (!можноПоложить(партия, карта)) {
      подсказкаОдинРаз = текущая === 'атака'
        ? 'Сейчас этой картой ходить нельзя'
        : 'Подкинуть можно только карту того же достоинства, что уже на столе';
      перерисовать();
      return;
    }
    положитьВАтаку(партия, 'человек', индекс);
    выбраннаяКарта = null;
    продолжить();
    return;
  }

  if (текущая === 'защита') {
    // Ищем, какие карты на столе эта карта вообще может побить.
    const цели = [];
    партия.стол.forEach(function (пара, i) {
      if (!пара.защита && бьёт(карта, пара.атака, партия.козырь)) цели.push(i);
    });
    if (цели.length === 0) {
      подсказкаОдинРаз = 'Этой картой не отбиться';
      перерисовать();
      return;
    }
    if (цели.length === 1) {
      // Крыть нечего выбирать — сразу бьём единственную подходящую карту.
      отбить(партия, цели[0], индекс);
      выбраннаяКарта = null;
      продолжить();
      return;
    }
    выбраннаяКарта = (выбраннаяКарта === индекс) ? null : индекс;
    перерисовать();
  }
}

function тапПоПаре(индексПары) {
  if (!партия || партия.завершена) return;
  if (фаза(партия) !== 'защита' || ктоХодит(партия) !== 'человек') return;
  if (выбраннаяКарта === null) return;
  if (!отбить(партия, индексПары, выбраннаяКарта)) return;
  выбраннаяКарта = null;
  продолжить();
}

function нажатьБито() {
  if (!партия || партия.завершена) return;
  const текущая = фаза(партия);
  if (партия.атакует !== 'человек') return;
  if (текущая !== 'подкидывание' && текущая !== 'докидывание') return;
  завершитьПодход(партия);
  выбраннаяКарта = null;
  продолжить();
}

function нажатьБеру() {
  if (!партия || партия.завершена) return;
  if (фаза(партия) !== 'защита' || ктоХодит(партия) !== 'человек') return;
  объявитьБеру(партия);
  выбраннаяКарта = null;
  продолжить();
}

/** Новая партия с нуля: старый таймер гасим, всё состояние создаём заново. */
function начатьПартию() {
  if (таймер !== null) {
    clearTimeout(таймер);
    таймер = null;
  }
  выбраннаяКарта = null;
  подсказкаОдинРаз = null;
  партия = создатьПартию();
  показатьЭкран('экран-игры');
  подобратьРазмерКарты();
  продолжить();
}

function запустить() {
  подобратьРазмерКарты();
  эл('кнопка-играть').addEventListener('click', начатьПартию);
  эл('кнопка-ещё').addEventListener('click', начатьПартию);
  эл('кнопка-завершить').addEventListener('click', нажатьБито);
  эл('кнопка-беру').addEventListener('click', нажатьБеру);
  // Поворот экрана или смена размера окна — пересчитываем карты и рисуем заново.
  window.addEventListener('resize', function () {
    подобратьРазмерКарты();
    перерисовать();
  });
}

