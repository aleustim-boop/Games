let таймер = null;              // отложенный ход бота
/* Плашка итога всплывает не сразу, а через паузу — чтобы игрок успел увидеть
   последний ход. За эту паузу экран может смениться (человек вышел в меню,
   сеть увела на экран с кодом комнаты), и тогда плашка легла бы поверх
   чужого экрана. Поэтому её ожидание держим отдельно от хода бота: так его
   можно погасить, не трогая партию. */
let таймерИтога = null;
let итогЗасчитан = false;       // результат партии уже записан в серию и рекорды

/* Сколько рука не принимает касаний сразу после нажатия кнопки. Окно завели
   от «самоходной» карты: палец, нажавший «Бито» или «Готово», вторым
   касанием задевал руку, и карта улетала на стол сама собой.

   Число не выдумано, а замерено в браузере (замерялка тестировщика лежит
   в tests/замер-глухоты-в-браузере.js, повторить можно одной строкой):
     — рука перерисовывается через 1–3 мс после нажатия кнопки, то есть
       уже на третьей миллисекунде тап по карте — законный ход;
     — при 350 мс пропадали настоящие тапы на 150, 200 и 330 мс:
       окно съедало ход, который человек делал осознанно;
     — второе касание того же нажатия укладывается в сотню миллисекунд,
       поэтому от него 150 хватает с запасом;
     — за 28 нажатий ни один «хвост» касания до карты не долетел вовсе:
       между рукой и кнопками 5–9 точек, но панель кнопок держит своё
       место и принимает такое касание на себя.

   Чего мы НЕ знаем: на настоящем телефоне бывает «призрачный клик» —
   он приходит примерно через 300 мс после отрыва пальца. В десктопном
   браузере его не воспроизвести, замера по нему нет. Расчёт тот же:
   придёт он в ту же точку, где панель кнопок, а не карта.

   Поэтому окно не убрано совсем, а укорочено: вёрстка когда-нибудь
   поменяется, зазор станет больше — и защита снова понадобится. */
const ГЛУХОТА_ПОСЛЕ_КНОПКИ = 150;
let рукаГлухаДо = 0;
let ждёмОтветПроВыход = false;  // висит вопрос «точно выйти?», партия на паузе
const размерКарты = { ширина: 48, высота: 70 };

/* Строка подсказки состоит из двух частей:
     «событие» — что только что произошло,
     «действие» — что от человека ждут прямо сейчас (висит всегда).
   Так сообщение об ошибке или о ходе бота больше не затирает насовсем
   главное — напоминание, что делать.

   Событие само по себе больше не стирается: оно висит, пока не случится
   следующее. Живой игрок жаловался прямо: «отвернулся на пять секунд —
   надпись пропала, посмотреть, что было, негде». Отдельного окошка
   с историей ходов на телефоне не завести, места нет, а последняя новость
   на экране стоит ноль пикселей — строка подсказки и так там стоит.

   Через ПОКАЗ_СОБЫТИЯ событие только «остывает»: текст остаётся, но с него
   снимается пометка свежести, по которой оформление его подсвечивает.
   Внешне это выглядит как раньше — вспыхнуло и успокоилось, — только
   прочитать написанное можно и через минуту. */
let событие = null;             // текст, который сейчас стоит в строке (или null)
let событиеДо = 0;              // время (мс), до которого он считается свежим
let паузаСобытия = ПАУЗА_ПОД_СОБЫТИЕ;   // сколько бот выжидает под него
let таймерСобытия = null;       // по нему событие остывает

/* Отдельно храним последний рассказ о ходе — тот, к которому строка
   возвращается после слов отказа. Отказы («сейчас ходит соперник»,
   «этой картой не отбиться») сюда не пишутся никогда, поэтому сколько бы
   их ни было подряд, рассказ о ходе соперника не потеряется. */
let рассказ = null;
let рассказДо = 0;
let паузаРассказа = ПАУЗА_ПОД_СОБЫТИЕ;

// Об одном и том же пропавшем элементе ругаемся один раз: перерисовка идёт
// десятки раз за партию, и повторы только засоряют консоль.
const ужеРугались = Object.create(null);

function эл(id) {
  const узел = document.getElementById(id);
  if (!узел && !ужеРугались[id]) {
    ужеРугались[id] = true;
    console.warn('Игра: в разметке нет элемента «' + id + '». ' +
                 'Часть экрана не отрисуется; возможно, браузер показывает старую страницу.');
  }
  return узел;
}

/** Записать текст в элемент, если он есть в разметке. */
function написать(id, текст) {
  const узел = эл(id);
  if (узел) узел.textContent = текст;
}

/**
 * Написать в рамку под заголовком итога — ту, где обычно стоит «Побед подряд: 3».
 * Пустой текст прячет её совсем: пустая рамка с обводкой и заливкой видна
 * как полоска ни о чём и только мешает читать экран.
 */
function написатьВРамкуИтога(текст) {
  написать('серия-итога', текст || '');
  показатьЭлемент('серия-итога', Boolean(текст));
}

/** Показать или спрятать элемент, если он есть в разметке. */
function показатьЭлемент(id, видно) {
  const узел = эл(id);
  if (узел) узел.classList.toggle('скрыт', !видно);
}

/** Название карты для сообщений: «10♠». */
function названиеКарты(карта) {
  return карта.имя + карта.масть;
}

/**
 * Правильно склоняем слово «карта» после числа: 1 карта, 2 карты, 5 карт.
 * Второй аргумент — винительный падеж («забрал 1 карту»).
 */
function словоКарты(сколько, винительный) {
  const двеПоследние = сколько % 100;
  const последняя = сколько % 10;
  if (двеПоследние >= 11 && двеПоследние <= 14) return 'карт';
  if (последняя === 1) return винительный ? 'карту' : 'карта';
  if (последняя >= 2 && последняя <= 4) return 'карты';
  return 'карт';
}

/**
 * Поставить текст в строку подсказки. Общая часть у рассказа о ходе
 * и у слов отказа: обоим нужно лечь в строку, завести срок свежести
 * и сказать боту, сколько ждать.
 */
function поставитьСообщение(текст, свежесть, паузаБота) {
  const держим = свежесть || ПОКАЗ_СОБЫТИЯ;
  событие = текст;
  событиеДо = Date.now() + держим;
  паузаСобытия = паузаБота || ПАУЗА_ПОД_СОБЫТИЕ;
  if (таймерСобытия !== null) clearTimeout(таймерСобытия);
  таймерСобытия = setTimeout(function () {
    таймерСобытия = null;
    // Текст не трогаем — перерисовываем строку, чтобы снялась пометка свежести.
    if (партия) рисоватьПодсказкуИКнопки();
  }, держим);
}

/**
 * Показать рассказ о том, что случилось. Текст остаётся на экране до
 * следующего события; через заданное время он лишь перестаёт считаться
 * свежим (гаснет подсветка).
 *
 * Третьим доводом можно сказать, сколько бот выжидает под это сообщение:
 * под свой ход человека — меньше, под уборку стола — больше. Не сказали —
 * берётся обычная ПАУЗА_ПОД_СОБЫТИЕ.
 */
function показатьСобытие(текст, свежесть, паузаБота) {
  поставитьСообщение(текст, свежесть, паузаБота);
  // Запоминаем отдельно: именно сюда строка вернётся после слов отказа.
  рассказ = текст;
  рассказДо = событиеДо;
  паузаРассказа = паузаСобытия;
}

/**
 * Показать слова отказа, не отняв у человека рассказ о ходе. Отказ висит
 * своё короткое время, а потом рассказ возвращается и досиживает остаток.
 * Случится за это время что-то новое — показатьСобытие погасит наш возврат
 * само: свежая новость всегда важнее возвращённой старой.
 *
 * Возвращаем не то, что было в строке за миг до отказа, а последний
 * настоящий рассказ о ходе. Разница видна на двух отказах подряд —
 * а это обычное дело: нетерпеливый человек тапает по картам, пока
 * соперник думает. Раньше второй отказ запоминал «на возврат» первый,
 * и рассказ о ходе соперника пропадал совсем: пока сообщения гасли
 * за три секунды, это было незаметно, а теперь они висят до следующего
 * хода, и вместо «Соперник подкинул Д♦» человек до конца хода смотрел бы
 * на «Сейчас ходит соперник».
 */
function показатьОтказ(текст) {
  поставитьСообщение(текст, ПОКАЗ_СЛОВ_ОТКАЗА, ПАУЗА_ПОД_СОБЫТИЕ);
  // Возвращать нечего: рассказа о ходе ещё не было вовсе.
  if (!рассказ) return;
  clearTimeout(таймерСобытия);
  таймерСобытия = setTimeout(function () {
    таймерСобытия = null;
    вернутьРассказ();
    if (партия) рисоватьПодсказкуИКнопки();
  }, ПОКАЗ_СЛОВ_ОТКАЗА);
}

/**
 * Вернуть в строку рассказ о ходе после слов отказа. Свежесть могла
 * кончиться, пока висел отказ, — тогда возвращаем текст сразу остывшим:
 * пропасть совсем он не должен, читать его человек вправе и потом.
 */
function вернутьРассказ() {
  const остаток = Math.max(0, рассказДо - Date.now());
  if (остаток > 0) {
    поставитьСообщение(рассказ, остаток, паузаРассказа);
    return;
  }
  событие = рассказ;
  событиеДо = 0;
  паузаСобытия = паузаРассказа;
}

/** Сколько миллисекунд событие ещё должно повисеть, чтобы его успели прочитать. */
function остатокСобытия() {
  if (!событие) return 0;
  return Math.max(0, событиеДо - Date.now());
}

/**
 * Сколько игра выжидает под сообщение. Само сообщение висит дольше,
 * но заставлять игрока ждать все три секунды между ходами бота незачем.
 * Потолок у каждого сообщения свой — его задаёт показатьСобытие.
 */
function ждатьПодСобытие() {
  return Math.min(остатокСобытия(), паузаСобытия);
}

/** Убрать сообщение совсем (новая партия, выход в меню). */
function убратьСобытие() {
  if (таймерСобытия !== null) clearTimeout(таймерСобытия);
  таймерСобытия = null;
  событие = null;
  событиеДо = 0;
  паузаСобытия = ПАУЗА_ПОД_СОБЫТИЕ;
  // Вместе с событием забываем и рассказ: возвращаться к вестям из прошлой
  // партии нельзя — карты уже другие.
  рассказ = null;
  рассказДо = 0;
  паузаРассказа = ПАУЗА_ПОД_СОБЫТИЕ;
}

/** Отменить отложенный показ плашки итога: показывать её уже некому или нечему. */
function отменитьПоказИтога() {
  if (таймерИтога === null) return;
  clearTimeout(таймерИтога);
  таймерИтога = null;
}

/** Показать один из трёх экранов, остальные спрятать. */
function показатьЭкран(id) {
  // Уходим со стола — отложенная плашка итога больше не нужна: иначе она
  // всплывёт поверх меню или экрана с кодом комнаты и перекроет кнопки.
  if (id !== 'экран-игры') отменитьПоказИтога();
  for (const экран of document.querySelectorAll('.экран')) {
    экран.classList.toggle('экран--виден', экран.id === id);
  }
  // Итог и вопрос про выход показываются по-особому — плашкой поверх стола.
  // При обычной смене экрана этот режим снимаем со всех.
  for (const экран of document.querySelectorAll('.экран')) {
    экран.classList.remove('экран--поверх');
  }
}

/** Стоит ли человек прямо сейчас у игрового стола. */
function этоЭкранИгры() {
  const стол = эл('экран-игры');
  return Boolean(стол && стол.classList.contains('экран--виден'));
}

/**
 * Показать итог партии плашкой поверх стола: игровой экран не прячем,
 * чтобы было видно, чем всё кончилось.
 */
function показатьПлашкуИтога() {
  const итог = эл('экран-результата');
  if (!итог) return;
  итог.classList.add('экран--поверх');
  итог.classList.add('экран--виден');
}

/**
 * Узнать настоящий размер карты — тот, который получился в оформлении.
 * Своей формулы у игры больше нет: раньше она повторяла расчёт из style.css,
 * и стоило дизайнеру поменять там хоть одно число, как размеры расходились
 * и веер раскладывался с щелями. Теперь спрашиваем у браузера: ставим
 * невидимую карту, меряем её и по этому размеру раскладываем руку.
 */
function измеритьКарту() {
  const щуп = document.createElement('div');
  щуп.className = 'карта';
  щуп.style.position = 'absolute';
  щуп.style.left = '-9999px';
  щуп.style.visibility = 'hidden';
  document.body.appendChild(щуп);
  const место = щуп.getBoundingClientRect();
  document.body.removeChild(щуп);
  // Ноль означает, что оформление ещё не загрузилось: тогда оставляем прежние
  // значения, иначе рука схлопнется в точку.
  if (место.height > 0 && место.width > 0) {
    размерКарты.высота = место.height;
    размерКарты.ширина = место.width;
  }
}

/**
 * Сказать оформлению, какой ширины карта помещается в это окно: по ширине
 * экрана должно вставать шесть карт — столько их в руке при раздаче.
 * Насколько карта влезет по высоте и в какие пределы уложится, решает
 * style.css, а мы потом просто меряем, что получилось.
 */
function подобратьРазмерКарты() {
  const поШирине = Math.floor((window.innerWidth - 16) / 6) * ПРОПОРЦИЯ_КАРТЫ;
  document.documentElement.style.setProperty('--высота-карты', Math.round(поШирине) + 'px');
  измеритьКарту();
}

/* Своя пометка на каждую масть. Раньше карта говорила оформлению только
   «красная или чёрная», и отличить пику от трефы было нечем: разбирать
   значок внутри карты оформление не умеет. Живой игрок на это и жаловался —
   «не видно, крест это или пика», особенно когда от карты в веере видна
   полоска в несколько точек.

   С этими пометками style.css может раскрасить масти по-разному (например,
   трефы зелёным, бубны синим). Сама игра ими не пользуется и от них
   не меняется: пока оформление их не подхватит, карты выглядят как прежде. */
const КЛАСС_МАСТИ = {
  '♠': 'карта--пики',
  '♥': 'карта--черви',
  '♦': 'карта--бубны',
  '♣': 'карта--трефы'
};

/** Собрать картинку одной карты. */
function элементКарты(карта, добавочныйКласс) {
  const узел = document.createElement('div');
  узел.className = 'карта';
  if (КРАСНЫЕ_МАСТИ.indexOf(карта.масть) !== -1) узел.classList.add('карта--красная');
  // Пометка масти. Её нет у карты-невидимки (чужая рука приходит без мастей) —
  // и это правильно: наружу не должно уйти ничего про чужие карты.
  const пометкаМасти = КЛАСС_МАСТИ[карта.масть];
  if (пометкаМасти) узел.classList.add(пометкаМасти);
  if (добавочныйКласс) узел.classList.add(добавочныйКласс);

  // Угол собираем из двух частей: достоинство и масть — отдельные элементы.
  // Так они всегда встают столбиком, а не зависят от переноса строки.
  const угол = document.createElement('div');
  угол.className = 'карта__угол';
  const номинал = document.createElement('span');
  номинал.className = 'карта__номинал';
  номинал.textContent = карта.имя;
  const мастьВУглу = document.createElement('span');
  мастьВУглу.className = 'карта__масть-угла';
  мастьВУглу.textContent = карта.масть;
  угол.appendChild(номинал);
  угол.appendChild(мастьВУглу);

  const масть = document.createElement('div');
  масть.className = 'карта__масть';
  масть.textContent = карта.масть;

  узел.appendChild(угол);
  узел.appendChild(масть);
  return узел;
}

/** Карта рубашкой вверх. */
function элементРубашки() {
  const узел = document.createElement('div');
  узел.className = 'карта карта--рубашка';
  return узел;
}

/**
 * Шаг между картами в ряду. Он же — ширина полоски, которая остаётся видна
 * от каждой карты: именно по ней игрок целится пальцем.
 */
function шагВРяду(ширинаКарты, картВРяду, доступно) {
  if (картВРяду <= 1) return 0;
  return Math.min(ширинаКарты + ЗАЗОР_КАРТ, (доступно - ширинаКарты) / (картВРяду - 1));
}

/**
 * Сказать оформлению, какой ширины видна каждая карта в этом веере.
 *
 * Шаг между картами — он же ширина оставшейся видимой полоски: по ней
 * игрок целится пальцем, и от неё зависит, какого размера подпись на карте
 * ещё можно прочитать. Считает эту ширину игра (она знает, сколько карт
 * и сколько места), а нужна она оформлению — вот и передаём числом,
 * чтобы style.css не угадывал её по количеству карт.
 */
function записатьШагВеера(контейнер, шаг) {
  // Ноль означает, что карта в ряду одна: она видна целиком, во всю ширину.
  const полоска = шаг > 0 ? шаг : размерКарты.ширина;
  контейнер.style.setProperty('--шаг-карт', Math.round(полоска) + 'px');
}

/**
 * Разложить карты веером внахлёст: считаем шаг так, чтобы любое
 * количество карт уместилось в ширину экрана.
 */
function разложитьВеером(контейнер, отступСверху) {
  const карты = контейнер.children;
  if (карты.length === 0) return;
  const доступно = контейнер.clientWidth || window.innerWidth;
  const шаг = шагВРяду(размерКарты.ширина, карты.length, доступно);
  const занято = размерКарты.ширина + шаг * (карты.length - 1);
  const старт = Math.max(0, (доступно - занято) / 2);
  for (let i = 0; i < карты.length; i++) {
    карты[i].style.left = Math.round(старт + шаг * i) + 'px';
    карты[i].style.top = отступСверху + 'px';
  }
  записатьШагВеера(контейнер, шаг);
}

/* ---------------------------------------------------------------------
   Компания за столом

   За столом на шестерых веер рубашек показать негде: пять вееров в телефон
   не влезут физически. Поэтому каждый соперник показан строкой — имя,
   сколько у него карт и что с ним происходит прямо сейчас.

   Всё, что здесь спрашивается про очередь, берётся у сервера: он один
   знает, кто уже сказал «пас». В игре с ботом и вдвоём списка мест нет
   вовсе, и стол рисуется по-старому — веером рубашек одного соперника.
   --------------------------------------------------------------------- */

/** Список мест от сервера — или null, если играем с ботом либо вдвоём. */
function местаКомпании() {
  return партия && Array.isArray(партия.застолом) ? партия.застолом : null;
}

/** Играем ли компанией: за столом больше двоих. */
function этоКомпания() {
  const места = местаКомпании();
  return Boolean(места) && места.length > 2;
}

/**
 * Моё ли сейчас слово. За столом компанией верим серверу: слово обходит
 * по кругу всех, кто ещё не спасовал, а этого списка у браузера нет.
 * В игре с ботом и вдвоём считаем как считали — по своим правилам.
 */
function сейчасМойХод() {
  if (!партия) return false;
  if (местаКомпании()) return партия.яХожу === true;
  return ктоХодит(партия) === 'человек';
}

/** Я ли сейчас отбиваюсь. */
function этоЯОтбиваюсь() {
  if (!партия) return false;
  if (местаКомпании()) return партия.яОтбиваюсь === true;
  return защищается(партия) === 'человек';
}

/** Разрешено ли мне сейчас класть карту в атаку (подкидывать). */
function мнеМожноПодкинуть() {
  if (!партия) return false;
  if (местаКомпании()) return партия.могуПодкинуть === true;
  return партия.атакует === 'человек';
}

/** Как зовут соперника, помеченного признаком («ходит» или «отбивается»). */
function имяТого(признак) {
  const места = местаКомпании() || [];
  for (const место of места) {
    if (место[признак] && !место.этоЯ) return место.имя;
  }
  return '';
}

/** Это место — мой напарник по игре парами. */
function этоМойНапарник(место) {
  return Boolean(партия && партия.парами && место.напарник &&
                 место.напарник === партия.мойНомер);
}

/** Соперники по кругу, начиная с соседа слева: в том же порядке ходит стол. */
function соперникиПоКругу() {
  const места = местаКомпании();
  if (!места) return [];
  let моёМесто = 0;
  for (let i = 0; i < места.length; i++) {
    if (места[i].этоЯ) моёМесто = i;
  }
  const круг = [];
  for (let шаг = 1; шаг < места.length; шаг++) {
    круг.push(места[(моёМесто + шаг) % места.length]);
  }
  return круг;
}

/**
 * Что с этим игроком прямо сейчас — одним словом. Порядок важен: сначала
 * то, из-за чего он вообще не играет (ушёл, кончились карты, пропала
 * связь), и только потом очередь хода. Иначе за столом висит «ходит»,
 * а человек не понимает, почему ничего не происходит.
 */
function состояниеСоперника(место) {
  if (место.ушёл) return 'ушёл';
  if (место.выбыл) return 'без карт';
  if (место.наСвязи === false) return 'нет связи';
  if (место.отбивается) return 'отбивается';
  if (место.ходит) return 'ходит';
  return '';
}

/**
 * Кто он за этим столом: играет со мной заодно или это робот.
 *
 * Слово нарочно короткое. Восемь букв («напарник») на экране шириной
 * 280 точек съедали пол-плашки, и от имени оставалась одна буква с
 * многоточием — оформлением это не лечится, места нет физически.
 *
 * Из двух коротких слов взято «свой», а не «пара»: «пара» в карточной
 * игре занято дважды — так зовут две карты одного достоинства и так же
 * называется связка «карта атаки плюс карта защиты» на столе. Новичок
 * прочитал бы её как подпись про карты, а не про человека. «Свой» же
 * ни с чем не спорит и говорит главное: он играет за меня.
 * Напарник опознаётся не только словом — у него своя пометка в оформлении.
 */
function рольСоперника(место) {
  if (этоМойНапарник(место)) return 'свой';
  return место.этоБот ? 'бот' : '';
}

/** Одна подпись внутри плашки соперника. */
function ячейкаСоперника(плашка, класс, текст) {
  const узел = document.createElement('span');
  узел.className = класс;
  узел.textContent = текст;
  плашка.appendChild(узел);
  return узел;
}

/** Плашка одного соперника: имя, сколько карт и что с ним происходит. */
function плашкаСоперника(место) {
  const плашка = document.createElement('div');
  плашка.className = 'соперник';
  // Пометки классами — чтобы оформление могло выделить и того, кто ходит,
  // и того, кто уже не играет, не разбирая надписи.
  if (место.ходит) плашка.classList.add('соперник--ходит');
  if (место.отбивается) плашка.classList.add('соперник--отбивается');
  if (место.выбыл) плашка.classList.add('соперник--выбыл');
  if (место.ушёл) плашка.classList.add('соперник--ушёл');
  if (место.наСвязи === false) плашка.classList.add('соперник--нет-связи');
  if (место.этоБот) плашка.classList.add('соперник--бот');
  if (место.проиграл) плашка.classList.add('соперник--проиграл');
  if (этоМойНапарник(место)) плашка.classList.add('соперник--напарник');

  ячейкаСоперника(плашка, 'соперник__имя', место.имя);
  const роль = рольСоперника(место);
  if (роль) ячейкаСоперника(плашка, 'соперник__роль', роль);
  const карт = целоеИзОтвета(место.карт);
  /* «0 карт» посреди подхода читается как «игрока больше нет» — та же беда,
     что и в игре вдвоём. Выбывших и ушедших это не касается: у них ноль
     настоящий, а их карты уже не на столе, и про них всё скажет метка. */
  const своиКартыНаСтоле = укартСоперникаТолькоСтол(карт) && !место.выбыл && !место.ушёл;
  ячейкаСоперника(плашка, 'соперник__карт',
    своиКартыНаСтоле ? ТЕКСТ_ВСЁ_НА_СТОЛЕ : (карт + ' ' + словоКарты(карт)));
  const метка = состояниеСоперника(место);
  if (метка) ячейкаСоперника(плашка, 'соперник__метка', метка);
  return плашка;
}

/**
 * Полоса соперников. В разметке её нет — она появилась позже игры вдвоём,
 * поэтому создаём её из кода и кладём первой на игровом экране: соперники
 * сидят напротив, значит и на экране они сверху.
 */
function полосаСоперников() {
  const готовая = document.getElementById('соперники');
  if (готовая) return готовая;
  const экран = эл('экран-игры');
  if (!экран) return null;
  const полоса = document.createElement('div');
  полоса.id = 'соперники';
  полоса.className = 'соперники скрыт';
  экран.insertBefore(полоса, экран.firstChild);
  return полоса;
}

/**
 * Кто сидит напротив. Вдвоём это привычный веер рубашек, компанией —
 * полоса плашек: чужие карты не рисуем никогда, только их количество.
 */
function рисоватьСоперников() {
  const компания = этоКомпания();
  показатьЭлемент('рука-бота', !компания);
  const полоса = полосаСоперников();
  if (полоса) полоса.classList.toggle('скрыт', !компания);
  if (!компания) {
    рисоватьРукуБота();
    return;
  }
  if (!полоса) return;
  полоса.innerHTML = '';
  for (const место of соперникиПоКругу()) полоса.appendChild(плашкаСоперника(место));
}

/** Сколько карт у соперника напротив — в игре вдвоём он один. */
function картУСоперникаВдвоём() {
  const места = местаКомпании();
  if (места) {
    for (const место of места) {
      if (!место.этоЯ) return целоеИзОтвета(место.карт);
    }
    return 0;
  }
  return партия.руки.бот ? партия.руки.бот.length : 0;
}

function рисоватьРукуБота() {
  const веер = эл('карты-бота');
  if (!веер) return;
  const сколько = картУСоперникаВдвоём();
  веер.innerHTML = '';
  for (let i = 0; i < сколько; i++) {
    веер.appendChild(элементРубашки());
  }
  разложитьВеером(веер, 2);
  // Пишем и уровень: иначе после «Играть ещё» непонятно, с кем сейчас играешь.
  // В игре вдвоём уровня нет вовсе — там за столом живой человек.
  const кто = этоСетеваяИгра()
    ? 'Друг'
    : партия.сложность.charAt(0).toUpperCase() + партия.сложность.slice(1) + ' соперник';
  написать('счётчик-бота', кто + ': ' + хвостСчётчикаСоперника(сколько));
}

/**
 * Чем заканчивается подпись под картами соперника. Обычно это просто число
 * карт, но у нуля есть два разных смысла, и путать их нельзя.
 *
 * «0 карт» человек читает как «соперника уже нет, игра сломалась» — так
 * и случилось у живого новичка: бот выложил последнюю карту, она лежала
 * на столе, подход не кончился, а сверху висело «Сложный соперник: 0 карт»
 * все семнадцать секунд, пока человек думал. Надпись не врала — врало
 * слово: счётчик про руку, а читается как «карты в игре».
 *
 * Правила при этом верные, и трогать их не надо: пока стол не убран, карты
 * соперника лежат на нём и вернутся к нему, если он берёт. Поэтому говорим
 * прямо, где они, и заодно видно, что соперник из партии не исчез.
 */
function хвостСчётчикаСоперника(сколько) {
  if (укартСоперникаТолькоСтол(сколько)) return ТЕКСТ_ВСЁ_НА_СТОЛЕ;
  return сколько + ' ' + словоКарты(сколько);
}

/* Короткая замена числу «0». Длинную фразу сюда не поставить: подпись
   соперника рисуется одной строкой и обрезается многоточием, а в компании
   та же мысль должна влезть в плашку шириной 128 точек. «Всё на столе»
   говорит и что рука пуста (карт не осталось совсем), и где эти карты. */
const ТЕКСТ_ВСЁ_НА_СТОЛЕ = 'всё на столе';

/**
 * Тот самый случай: карт в руке ноль, но игрок из партии не выбыл — его
 * карты лежат на столе и вернутся к нему, если он берёт.
 * Партия завершена — считаем обычным нулём: в сетевой партии стол приходит
 * от сервера и может оказаться непустым уже после конца игры, и тогда под
 * плашкой «Друг вышел из игры» висела бы надпись про карты на столе.
 */
function укартСоперникаТолькоСтол(сколько) {
  return сколько === 0 && !партия.завершена && партия.стол.length > 0;
}

function рисоватьКолоду() {
  const козырь = эл('козырная-карта');
  const верх = эл('верх-колоды');
  const счётчик = эл('счётчик-колоды');
  if (козырь) козырь.innerHTML = '';
  if (верх) верх.innerHTML = '';

  // Козырная карта видна, пока она ещё в колоде; рубашка — пока над ней есть карты.
  if (козырь && партия.колода.length > 0) козырь.appendChild(элементКарты(партия.козырнаяКарта));
  if (верх && партия.колода.length > 1) верх.appendChild(элементРубашки());

  // Подписываем счётчик и не прячем его: когда колода кончилась,
  // важно прямо сказать об этом, а не убирать угол с экрана.
  const осталось = партия.колода.length;
  if (счётчик) {
    счётчик.textContent = осталось > 0
      ? 'В колоде ' + осталось + ' ' + словоКарты(осталось)
      : 'Колода пуста';
    счётчик.classList.remove('скрыт');
  }
  // Масть в сетевой партии приходит от сервера: обычно она есть всегда,
  // но при пустой в рамке висело бы «Козырь » с лишним пробелом на конце.
  написать('метка-козыря', партия.козырь ? 'Козырь ' + партия.козырь : 'Козырь');
}

function рисоватьСтол() {
  const стол = эл('стол');
  if (!стол) return;
  стол.innerHTML = '';
  const человекЗащищается = этоЯОтбиваюсь() && фаза(партия) === 'защита';
  const поднятая = выбраннаяКарта !== null ? партия.руки.человек[выбраннаяКарта] : null;

  партия.стол.forEach(function (пара, индекс) {
    const узел = document.createElement('div');
    узел.className = 'пара';
    узел.appendChild(элементКарты(пара.атака, 'карта--атака'));
    if (пара.защита) узел.appendChild(элементКарты(пара.защита, 'карта--защита'));

    // Подсвечиваем те карты, которые человек может побить выбранной картой.
    if (человекЗащищается && поднятая && !пара.защита &&
        бьёт(поднятая, пара.атака, партия.козырь)) {
      узел.classList.add('пара--цель');
    }
    узел.addEventListener('click', function () { тапПоПаре(индекс); });
    стол.appendChild(узел);
  });
}

/* Когда рука раскладывается в два ряда.
   Раньше порогом было 20 карт и ряд не ниже 40 точек — из-за этого на
   невысоком экране два ряда не включались никогда, а перед самым порогом
   получался провал: 19 карт — полоска 17 точек, 20 карт — сразу 30.
   Теперь порог низкий, ряд может быть мелким, а решает сравнение: два ряда
   берём, только если видимая полоска карты станет заметно шире. Мелкая
   карта хуже читается, но подпись оформление уменьшает ступенями, а вот
   попасть пальцем в полоску шириной 6 точек нельзя вовсе. */
const ПОРОГ_ДВУХ_РЯДОВ = 12;
const МИН_ВЫСОТА_В_РЯДУ = 24;
const ВЫГОДА_ДВУХ_РЯДОВ = 1.15;   // насколько шире должна стать полоска
const ЗАЗОР_КАРТ = 4;             // просвет между картами, пока рука не тесная
const ОТСТУП_РУКИ = 14;    // запас сверху: выбранная карта приподнимается
/* На сколько поднимается выбранная карта, когда рука лежит в два ряда.
   Это своя величина, с зазором между рядами она не связана.
   Больше 14 брать нельзя: столько запаса оставлено сверху полоски руки,
   и карта верхнего ряда полезла бы на строку подсказки. Снизу подъём
   закрывает у верхних карт только нижние 8 точек — номинал с мастью
   сидят в верхнем углу и остаются видны. */
const ПОДЪЁМ_В_ДВА_РЯДА = 14;
// Зазор между рядами. При двух точках щель тоньше рамки карты, и ряды
// сливаются в сплошную сетку. Больше шести брать нельзя: на телефоне
// шириной 360 точек ряд становится ниже порога и рука схлопывается в один.
const ЗАЗОР_РЯДОВ = 6;

/**
 * Нужны ли два ряда и какой высоты будут в них карты. Возвращает 0, если
 * рука остаётся в один ряд: карт мало, высоты не хватает или два ряда
 * ничего не выигрывают.
 */
function высотаРядаДляДвух(картВРуке, доступно) {
  if (картВРуке < ПОРОГ_ДВУХ_РЯДОВ) return 0;

  const рука = эл('карты-человека');
  // Высоту полоски берём из вёрстки, а не считаем заново.
  const полоска = рука && рука.clientHeight > 0 ? рука.clientHeight : размерКарты.высота + 18;
  const высотаРяда = Math.floor((полоска - ОТСТУП_РУКИ - ЗАЗОР_РЯДОВ) / 2);
  if (высотаРяда < МИН_ВЫСОТА_В_РЯДУ) return 0;

  // Считаем оба варианта и сравниваем то, ради чего всё затевалось, —
  // ширину полоски, в которую надо попасть пальцем.
  const вОдинРяд = шагВРяду(размерКарты.ширина, картВРуке, доступно);
  const вДваРяда = шагВРяду(размерКарты.ширина, Math.ceil(картВРуке / 2), доступно);
  return вДваРяда > вОдинРяд * ВЫГОДА_ДВУХ_РЯДОВ ? высотаРяда : 0;
}

/**
 * Разложить руку в два ряда. В одном ряду 35 карт превращаются в полоски
 * по 9 точек, и палец попадает в соседнюю; в двух рядах карт вдвое меньше,
 * и каждая шире.
 */
function разложитьДвумяРядами(контейнер, высотаРяда) {
  const карты = контейнер.children;
  if (карты.length === 0) return;
  const ширинаКарты = размерКарты.ширина;   // по ширине карта не ужимается
  const доступно = контейнер.clientWidth || window.innerWidth;
  const вВерхнем = Math.ceil(карты.length / 2);
  const вНижнем = карты.length - вВерхнем;
  const шагВерхнего = шагВРяду(ширинаКарты, вВерхнем, доступно);
  const шагНижнего = шагВРяду(ширинаКарты, вНижнем, доступно);

  for (let i = 0; i < карты.length; i++) {
    const верхний = i < вВерхнем;
    const вРяду = верхний ? вВерхнем : вНижнем;
    const номерВРяду = верхний ? i : i - вВерхнем;
    const шаг = верхний ? шагВерхнего : шагНижнего;
    const занято = ширинаКарты + шаг * (вРяду - 1);
    const старт = Math.max(0, (доступно - занято) / 2);
    карты[i].style.left = Math.round(старт + шаг * номерВРяду) + 'px';
    карты[i].style.top = (верхний ? ОТСТУП_РУКИ : ОТСТУП_РУКИ + высотаРяда + ЗАЗОР_РЯДОВ) + 'px';
  }
  /* Оформлению отдаём самую узкую полоску из двух рядов: подпись должна
     читаться и в том ряду, где карты сжаты сильнее. Нулевой шаг бывает
     у ряда из одной карты — тогда меркой служит второй ряд. */
  записатьШагВеера(контейнер,
    Math.min(шагВерхнего || шагНижнего, шагНижнего || шагВерхнего));
}

/**
 * Можно ли сейчас сходить этой картой. Игра это и так знает — иначе не умела бы
 * отказывать; показываем знание игроку, чтобы он не считал в уме.
 * Не наш ход — возвращаем null: тогда карты остаются обычными, без пометок.
 */
function картаСейчасХодит(карта) {
  const текущая = фаза(партия);
  if (!сейчасМойХод()) return null;
  if (текущая === 'защита') {
    for (const пара of партия.стол) {
      if (!пара.защита && бьёт(карта, пара.атака, партия.козырь)) return true;
    }
    // В переводном ход можно не крыть, а перевести — такая карта тоже ходит.
    return можноПеревестиЭтой(карта);
  }
  if (текущая === 'атака' || текущая === 'подкидывание' || текущая === 'докидывание') {
    return можноПоложить(партия, карта);
  }
  return null;
}

/**
 * Отказ без карты под пальцем: человек нажал туда, где вздрагивать нечему
 * (карта соперника на столе, стопка колоды). Остаются слова и короткий
 * звук — но и этого хватает, чтобы нажатие не выглядело провалившимся.
 */
function отказатьСловами(текст) {
  звукОтказа();
  показатьОтказ(текст);
  // Отказ сервера может прийти, когда партии уже нет (человек вышел в меню,
  // пока ход летел): рисовать подсказку тогда нечем и незачем.
  if (партия) рисоватьПодсказкуИКнопки();
}

/**
 * Отказ по карте: пометка под пальцем плюс объяснение в подсказке.
 * Руку целиком не перерисовываем — иначе пометка отказа тут же исчезнет.
 */
function отказатьПоКарте(индекс, текст) {
  отказатьСловами(текст);
  const веер = эл('карты-человека');
  const узел = веер ? веер.children[индекс] : null;
  if (!узел) return;
  узел.classList.remove('карта--отказ');
  // Пауза в один кадр нужна, чтобы пометка сработала и на повторный тап
  // по той же карте: без неё браузер не заметит, что класс возвращали.
  requestAnimationFrame(function () {
    узел.classList.add('карта--отказ');
  });
  setTimeout(function () { узел.classList.remove('карта--отказ'); }, ПОКАЗ_ОТКАЗА);
}

function рисоватьРукуЧеловека() {
  const веер = эл('карты-человека');
  if (!веер) return;
  веер.innerHTML = '';

  const доступно = веер.clientWidth || window.innerWidth;
  const высотаРяда = высотаРядаДляДвух(партия.руки.человек.length, доступно);

  партия.руки.человек.forEach(function (карта, индекс) {
    const узел = элементКарты(карта);
    // Подсказка глазами: чем можно ходить прямо сейчас, а чем нельзя.
    const ходит = картаСейчасХодит(карта);
    if (ходит === true) узел.classList.add('карта--можно');
    else if (ходит === false) узел.classList.add('карта--нельзя');
    if (высотаРяда) {
      // Ужимаем карту только по высоте: её не хватает на два ряда. Ширину
      // не трогаем — от неё оформление считает кегль подписи, а ужатая
      // пропорционально карта на невысоком экране выходит шириной в 21
      // точку, и номинал на ней уже не прочесть.
      узел.style.setProperty('--в', высотаРяда + 'px');
    }
    if (индекс === выбраннаяКарта) {
      узел.classList.add('карта--выбрана');
      // Подъём в два ряда не привязан к зазору — это своя величина.
      if (высотаРяда) узел.style.transform = 'translateY(-' + ПОДЪЁМ_В_ДВА_РЯДА + 'px)';
    }
    узел.addEventListener('click', function () { тапПоКартеЧеловека(индекс); });
    веер.appendChild(узел);
  });

  if (высотаРяда) разложитьДвумяРядами(веер, высотаРяда);
  else разложитьВеером(веер, ОТСТУП_РУКИ);
}

/** Есть ли у человека хоть одна карта, которую сейчас разрешено подкинуть. */
function естьЧемПодкинуть() {
  for (const карта of партия.руки.человек) {
    if (можноПоложить(партия, карта)) return true;
  }
  return false;
}

/** Есть ли чем крыть хоть одну карту на столе. */
function естьЧемОтбиться() {
  for (const пара of партия.стол) {
    if (пара.защита) continue;
    for (const карта of партия.руки.человек) {
      if (бьёт(карта, пара.атака, партия.козырь)) return true;
    }
  }
  return false;
}

/**
 * Можно ли этой картой перевести ход (только в переводном дураке).
 *
 * За столом компанией возможность перевода считает сервер: она зависит
 * от того, сколько карт у следующего игрока, а чужие руки браузеру
 * не присылают. От самой карты там зависит одно — её достоинство:
 * прочие условия перевода одинаковы для всей руки. В игре с ботом
 * правила лежат рядом, поэтому спрашиваем их напрямую.
 */
function можноПеревестиЭтой(карта) {
  if (!партия || !карта) return false;
  if (местаКомпании()) {
    return партия.могуПеревести === true &&
           достоинстваНаСтоле(партия).indexOf(карта.имя) !== -1;
  }
  return можноПеревести(партия, карта);
}

/** Есть ли в руке хоть одна карта, которой можно перевести ход. */
function естьЧемПеревести() {
  for (const карта of партия.руки.человек) {
    if (можноПеревестиЭтой(карта)) return true;
  }
  return false;
}

/** Что делать с поднятой картой — когда выбор есть, его надо назвать вслух. */
function текстВыбраннойКарты() {
  const карта = партия.руки.человек[выбраннаяКарта];
  if (карта && можноПеревестиЭтой(карта)) {
    // Этой картой можно и крыть, и переводить — называем оба выхода.
    for (const пара of партия.стол) {
      if (!пара.защита && бьёт(карта, пара.атака, партия.козырь)) {
        return 'Укажите карту на столе или нажмите «Перевести»';
      }
    }
    // Крыть ею нечего: остаётся только перевод, так и говорим.
    return 'Этой картой можно только перевести — нажмите «Перевести»';
  }
  return 'Укажите карту на столе, которую бьёте';
}

/** Что от человека ждут прямо сейчас. Эта строка видна всегда. */
function текстДействия() {
  const текущая = фаза(партия);
  const ходит = ктоХодит(партия);
  const человекАтакует = партия.атакует === 'человек';

  // За столом компанией всё рассказывается иначе: там мало сказать
  // «соперник», надо назвать, кто именно ходит и кто отбивается.
  if (этоКомпания()) return текстДействияВКомпании();

  if (текущая === 'атака') {
    return человекАтакует ? 'Ваш ход — выберите карту' : 'Соперник ходит…';
  }
  if (текущая === 'защита') {
    if (ходит !== 'человек') return 'Соперник отбивается…';
    if (выбраннаяКарта !== null) return текстВыбраннойКарты();
    // Перевод проверяем раньше защиты: крыть бывает нечем, а перевести можно.
    if (естьЧемПеревести()) return 'Отбивайтесь или переведите — выберите карту';
    // Не зовём выбирать карту, если крыть нечем: игра это знает заранее.
    return естьЧемОтбиться()
      ? 'Отбивайтесь — выберите карту'
      : 'Отбиться нечем — жмите «Беру»';
  }
  if (текущая === 'подкидывание') {
    if (!человекАтакует) return 'Соперник думает, что подкинуть…';
    return естьЧемПодкинуть()
      ? 'Можете подкинуть или нажать «Бито»'
      : 'Подкинуть нечем — нажмите «Бито»';
  }
  if (текущая === 'докидывание') {
    if (!человекАтакует) return 'Вы забираете карты. Соперник может подкинуть…';
    // Тексты нарочно короткие: вместе с рассказом о событии они должны
    // умещаться в две строки подсказки (около 90 знаков на двоих).
    return естьЧемПодкинуть()
      ? 'Соперник берёт — можно подкинуть или «Готово»'
      : 'Соперник берёт — подкинуть нечем, жмите «Готово»';
  }
  // Партия доиграна: между последним ходом и экраном итога строка не пустует.
  return 'Партия окончена';
}

/**
 * То же самое, но за столом компанией. Отдельно от игры вдвоём нарочно:
 * там довольно слова «соперник», а здесь соперников до пяти, и главный
 * вопрос человека — кто именно сейчас ходит и кто отбивается.
 *
 * Строки нарочно короткие: вместе с рассказом о событии они должны
 * умещаться в две строки подсказки (около 90 знаков на двоих).
 */
function текстДействияВКомпании() {
  const текущая = фаза(партия);
  if (текущая === 'конец') return 'Партия окончена';

  if (текущая === 'защита') {
    if (!этоЯОтбиваюсь()) {
      const кто = имяТого('отбивается');
      return (кто || 'Соперник') + ' отбивается…';
    }
    if (выбраннаяКарта !== null) return текстВыбраннойКарты();
    if (естьЧемПеревести()) return 'Отбивайтесь или переведите — выберите карту';
    return естьЧемОтбиться()
      ? 'Отбивайтесь — выберите карту'
      : 'Отбиться нечем — жмите «Беру»';
  }

  if (текущая === 'атака') {
    if (сейчасМойХод()) return 'Ваш ход — выберите карту';
    const кто = имяТого('ходит');
    return 'Ходит ' + (кто || 'соперник') + '…';
  }

  // Подкидывание и докидывание: слово обходит круг, и оно бывает не наше.
  const берёт = имяТого('отбивается');
  if (!(сейчасМойХод() && мнеМожноПодкинуть())) {
    if (текущая === 'докидывание') {
      return этоЯОтбиваюсь()
        ? 'Вы забираете карты — вам ещё могут подкинуть…'
        : (берёт || 'Соперник') + ' берёт карты — ждём остальных…';
    }
    const кто = имяТого('ходит');
    return кто ? кто + ' думает, что подкинуть…' : 'Ждём соперников…';
  }
  const хвост = естьЧемПодкинуть() ? 'подкиньте или «Пас»' : 'подкинуть нечем, жмите «Пас»';
  if (текущая === 'докидывание') return (берёт || 'Соперник') + ' берёт — ' + хвост;
  return 'Ваше слово: ' + хвост;
}

/**
 * Почему нажатие не сработало, когда слово не наше. Слова берём те же, что
 * в подсказке: вдвоём соперник один и зовётся «соперник», а за столом
 * компанией их до пяти — там называем имя, иначе непонятно, кого ждать.
 */
function текстНеВашХод() {
  const компания = этоКомпания();
  // Пока идёт защита, ждут именно отбивающегося — про него и говорим.
  if (фаза(партия) === 'защита' && !этоЯОтбиваюсь()) {
    const кто = компания ? имяТого('отбивается') : '';
    return 'Сейчас отбивается ' + (кто || 'соперник');
  }
  const кто = компания ? имяТого('ходит') : '';
  return 'Сейчас ходит ' + (кто || 'соперник');
}

/**
 * Могу ли я сейчас закончить свой подход — сказать «Бито», «Готово» или «Пас».
 * Вдвоём это по-прежнему право того, кто ходил. В компании подкидывать
 * могут все, кроме отбивающегося, поэтому спрашиваем сервер: чьё слово
 * сейчас и разрешено ли этому игроку класть карту.
 */
function мнеМожноЗакончитьПодход(текущая) {
  if (текущая !== 'подкидывание' && текущая !== 'докидывание') return false;
  if (этоКомпания()) return сейчасМойХод() && мнеМожноПодкинуть();
  return партия.атакует === 'человек';
}

/**
 * Надпись на кнопке конца подхода. Вдвоём всё как было: отбился соперник —
 * «Бито», забирает карты — «Готово». В компании эта же кнопка значит другое:
 * «я больше не подкидываю, пусть решают остальные», и это называется «Пас».
 */
function надписьЗавершения(текущая) {
  if (этоКомпания()) return 'Пас';
  return текущая === 'докидывание' ? 'Готово' : 'Бито';
}

/**
 * Кнопка «Перевести». В разметке её нет — перевод появился позже, поэтому
 * кнопку создаём из кода и кладём в ту же строку, где «Бито» и «Беру».
 */
function кнопкаПеревода() {
  const готовая = document.getElementById('кнопка-перевести');
  if (готовая) return готовая;
  const панель = эл('панель-кнопок');
  if (!панель) return null;
  const кнопка = document.createElement('button');
  кнопка.id = 'кнопка-перевести';
  кнопка.className = 'кнопка кнопка--перевод скрыт';
  кнопка.textContent = 'Перевести';
  кнопка.addEventListener('click', нажатьПеревести);
  панель.appendChild(кнопка);
  return кнопка;
}

/**
 * Куда писать текст подсказки: во вложенный span внутри коробки.
 * Коробка при этом стоит неподвижно и держит свою высоту, а цветная плашка
 * обтягивает текст — поэтому стол больше не подпрыгивает, когда сообщение
 * выросло в три строки, а через три секунды сложилось обратно в две.
 *
 * ЛОВУШКА для того, кто будет править это после нас: запись
 * «подсказка.textContent = …» прямо в коробку стирает всё, что внутри, —
 * первый же такой вызов уничтожит span, и дальше игра будет писать в пустоту.
 * Текст подсказки ставить только через эту функцию.
 *
 * Запасной путь. Telegram у части игроков отдаёт страницу из своей памяти,
 * старую — без вложенного span. Тогда пишем в саму коробку, как раньше:
 * высота опять будет прыгать, но подсказки будут видны, а без запасного пути
 * такие игроки увидели бы пустую строку и играли бы вообще без подсказок.
 */
function строкаПодсказки() {
  const коробка = эл('подсказка');
  if (!коробка) return null;
  // Намеренно без «эл»: отсутствие span — не поломка, ругаться в консоль не о чем.
  return document.getElementById('подсказка-текст') || коробка;
}

/** Строка подсказки и кнопки хода. */
function рисоватьПодсказкуИКнопки() {
  const текущая = фаза(партия);
  const действие = текстДействия();

  // Сначала рассказ о событии, через точку — напоминание, что делать.
  const подсказка = строкаПодсказки();
  if (подсказка) {
    подсказка.textContent = событие
      ? (действие ? событие + ' · ' + действие : событие)
      : действие;
    /* Обе пометки висят на тексте, а не на коробке: и та и другая рисуют
       плашку, а плашка должна обтягивать слова. Останься они на коробке —
       под коротким сообщением висел бы пустой цветной прямоугольник
       в три строки высотой. */
    /* Подсвечиваем только свежую новость. Остывшее сообщение остаётся
       на экране обычным текстом: прочитать, что случилось, можно и через
       минуту, но в глаза оно уже не бросается и с новостями не спорит. */
    подсказка.classList.toggle('подсказка--событие', Boolean(событие) && остатокСобытия() > 0);
    // Отдельная пометка «сейчас ходите вы» — её оформление задаёт style.css.
    подсказка.classList.toggle('подсказка--ваш-ход', сейчасМойХод());
  }

  const можноБито = мнеМожноЗакончитьПодход(текущая);
  const можноБеру = текущая === 'защита' && сейчасМойХод();
  /* Перевод показываем только на поднятую карту: одной и той же картой
     часто можно и отбиться, и перевести, и выбирать за человека нельзя.
     Пока карта не поднята, кнопке нечем работать — и её нет. */
  const можноПеревод = выбраннаяКарта !== null &&
                       можноПеревестиЭтой(партия.руки.человек[выбраннаяКарта]);

  написать('кнопка-завершить', надписьЗавершения(текущая));
  const завершить = эл('кнопка-завершить');
  // Пометка для оформления: «Пас» — это не то же самое, что «Бито».
  if (завершить) завершить.classList.toggle('кнопка--пас', этоКомпания());
  показатьЭлемент('кнопка-завершить', можноБито);
  показатьЭлемент('кнопка-беру', можноБеру);
  const перевод = кнопкаПеревода();
  if (перевод) перевод.classList.toggle('скрыт', !можноПеревод);
}

/** Единственная точка отрисовки: экран целиком собирается заново по состоянию. */
function перерисовать() {
  if (!партия) return;
  рисоватьСоперников();
  рисоватьКолоду();
  рисоватьСтол();
  рисоватьРукуЧеловека();
  рисоватьПодсказкуИКнопки();
}

/* ---------------------------------------------------------------------
   Ход игры: после каждого действия перерисовываем экран и,
   если очередь бота, ставим его ход на таймер.
   --------------------------------------------------------------------- */

/** Снимок стола перед чужим ходом — по нему потом поймём, что именно случилось. */
function снимокДляРассказа() {
  return {
    парНаСтоле: партия.стол.length,
    отбитые: партия.стол.map(function (пара) { return Boolean(пара.защита); }),
    картыСтола: картыСоСтола(),
    берёт: партия.берёт,
    защитник: защищается(партия),
    // Нужно, чтобы после подхода сказать, сколько карт пришло из колоды.
    вРукеЧеловека: партия.руки.человек ? партия.руки.человек.length : 0
  };
}

/** Все карты со стола по порядку: сначала та, которой ходили, следом — которой били. */
function картыСоСтола() {
  const карты = [];
  for (const пара of партия.стол) {
    карты.push(пара.атака);
    if (пара.защита) карты.push(пара.защита);
  }
  return карты;
}

/* Сколько забранных карт называем поимённо. Больше четырёх в строку
   подсказки не влезает, да и читать список из десяти названий на телефоне
   никто не станет — там уже важнее само число. */
const КАРТ_СПИСКОМ = 4;

/**
 * Чем кончился подход. Считать нужно ДО завершения подхода:
 * после него стол уже пуст и сказать нечего.
 *
 * Свои забранные карты называем поимённо: игрок жаловался, что понимал,
 * что именно забрал, только пересчитав руку. Чужие — числом: чем ходил
 * соперник, уже было сказано в своё время.
 */
function текстКонцаПодхода(карты, берёт, защитник, добрано) {
  const сколько = карты.length;
  if (берёт) {
    const слово = словоКарты(сколько, true);
    // Карты забрал соперник, а из колоды в это время добирали мы — про свой
    // добор человеку надо сказать в любом случае, чей бы ни был подход.
    if (защитник !== 'человек') {
      return приписатьДобор('Соперник забрал ' + сколько + ' ' + слово, добрано);
    }
    const текст = сколько <= КАРТ_СПИСКОМ
      ? 'Вы забрали ' + карты.map(названиеКарты).join(', ')
      : 'Вы забрали ' + сколько + ' ' + слово;
    return приписатьДобор(текст, добрано);
  }
  return приписатьДобор('Бито — в отбой ' + сколько + ' ' + словоКарты(сколько), добрано);
}

/**
 * Приписка про добор из колоды. Живой игрок сказал: «карты в руке сами
 * прибавляются, откуда у меня валет бубён — непонятно». Показывать добор
 * картинкой дорого, а одной строкой — ровно тот знак, которого он ждал.
 *
 * Слова считаны, а не подобраны на глаз. Строка подсказки высотой ровно
 * в две строки, и лишнее в ней не обрезается с хвоста, а срезается сверху
 * и снизу — то есть портится всё сообщение сразу. На телефоне 360 точек
 * в две строки влезает около 80 знаков, а самая длинная строка игры без
 * этой приписки — 76 знаков («Соперник сказал «Бито» — в отбой 4 карты ·
 * Ваш ход — выберите карту» и подобные). Значит на приписку есть
 * одиннадцать знаков, и полная фраза «, вы добрали 2 карты из колоды»
 * (30 знаков, строка вырастала до 97) в них не укладывается никак.
 *
 * Отсюда короткое «, добрали 2»: слово «добрать» в картах и значит
 * «взять из колоды», а рядом на экране стоит счётчик «В колоде 12 карт»,
 * так что откуда пришли эти карты, видно тут же. На деле строка выглядит
 * так: «Бито — в отбой 2 карты, добрали 1» или «Соперник забрал 5 карт,
 * добрали 3».
 */
function приписатьДобор(текст, добрано) {
  if (!добрано || добрано <= 0) return текст;
  return текст + ', добрали ' + добрано;
}

/**
 * Сколько карт пришло человеку именно из колоды. Считается после подхода:
 * рука выросла и на карты со стола (если он их забрал), и на добор,
 * поэтому взятое со стола вычитаем.
 */
function сколькоДобрали(былоВРуке, взятоСоСтола) {
  const стало = партия.руки.человек ? партия.руки.человек.length : 0;
  return Math.max(0, стало - былоВРуке - взятоСоСтола);
}

/** Подход закончился на этом ходу: стол уехал в отбой или в чью-то руку. */
function подходЗакончился(было) {
  return было.парНаСтоле > 0 && партия.стол.length === 0;
}

/** Что сделал бот: сравниваем стол до хода и после. */
function рассказатьОХодеБота(было) {
  // Подход закончился: стол опустел.
  if (подходЗакончился(было)) {
    const взятоСоСтола = было.берёт && было.защитник === 'человек' ? было.картыСтола.length : 0;
    const добрано = сколькоДобрали(было.вРукеЧеловека, взятоСоСтола);
    if (было.берёт) return текстКонцаПодхода(было.картыСтола, true, было.защитник, добрано);
    return приписатьДобор('Соперник сказал «Бито» — в отбой ' + было.картыСтола.length +
                          ' ' + словоКарты(было.картыСтола.length), добрано);
  }
  // Бот положил карту.
  if (партия.стол.length > было.парНаСтоле) {
    const карта = названиеКарты(партия.стол[партия.стол.length - 1].атака);
    if (было.парНаСтоле === 0) return 'Соперник ходит ' + карта;
    return 'Соперник подкинул ' + карта;
  }
  // Бот решил взять.
  if (!было.берёт && партия.берёт) return 'Соперник не смог отбиться';
  // Бот отбился: ищем пару, у которой появилась защита.
  for (let i = 0; i < партия.стол.length; i++) {
    if (партия.стол[i].защита && !было.отбитые[i]) {
      return 'Соперник отбил ' + названиеКарты(партия.стол[i].атака) +
             ' картой ' + названиеКарты(партия.стол[i].защита);
    }
  }
  return '';
}

/** Звук под ход бота: карты по столу шуршат иначе, чем забранная охапка. */
function озвучитьХодБота(было) {
  if (подходЗакончился(было)) {
    if (было.берёт) звукВзятия(); else звукКарты();
    return;
  }
  if (партия.стол.length > было.парНаСтоле) { звукКарты(); return; }   // положил карту
  if (!было.берёт && партия.берёт) { звукВзятия(); return; }          // решил взять
  for (let i = 0; i < партия.стол.length; i++) {
    if (партия.стол[i].защита && !было.отбитые[i]) { звукКарты(); return; }  // отбился
  }
}

/** Ход бота на экране: сходил — рассказали, что сделал. */
function сделатьХодБота() {
  таймер = null;
  // Партии может уже не быть: игрок вышел в меню, пока ход был отложен.
  if (!партия || партия.завершена) return;
  const было = снимокДляРассказа();
  ходБота(партия, 'бот');
  const рассказ = рассказатьОХодеБота(было);
  // Под уборку стола выжидаем дольше: там меняется весь экран разом.
  if (рассказ) {
    показатьСобытие(рассказ, ПОКАЗ_СОБЫТИЯ,
      подходЗакончился(было) ? ПАУЗА_ПОСЛЕ_ПОДХОДА : ПАУЗА_ПОД_СОБЫТИЕ);
  }
  озвучитьХодБота(было);
  продолжить();
}

function продолжить() {
  // Страховка для игры вдвоём: там ходы приходят с сервера, а бот не играет
  // вовсе. Проверка стоит в самой развилке — так ни один забытый путь
  // не сможет случайно разбудить робота посреди партии с живым другом.
  if (этоСетеваяИгра()) {
    перерисовать();
    return;
  }
  перерисовать();
  if (партия.завершена) {
    // Итог засчитываем прямо сейчас, а плашку показываем чуть позже.
    // Раньше и то и другое ждало показа: игрок успевал выйти в меню
    // за эти две секунды, и проигрыш просто не записывался.
    засчитатьИтог();
    отменитьПоказИтога();
    таймерИтога = setTimeout(показатьРезультат, Math.max(900, ждатьПодСобытие() + 500));
    return;
  }
  if (ктоХодит(партия) === 'бот') {
    // Бот не спешит: пока висит сообщение о прошлом событии, он ждёт.
    таймер = setTimeout(сделатьХодБота, Math.max(ЗАДЕРЖКА_БОТА, ждатьПодСобытие()));
  }
}

/**
 * Партия кончилась: записываем результат и звучим об этом.
 * Делается ровно один раз и сразу — до всяких показов и задержек,
 * чтобы выход в меню уже ничего не отменял.
 */
function засчитатьИтог() {
  if (итогЗасчитан || !партия) return;
  итогЗасчитан = true;
  if (партия.результат === 'бот') звукПобеды();
  else if (партия.результат === 'человек') звукПроигрыша();
  подвестиСерию(партия.результат);
}

/**
 * Заголовок итога и объяснение под ним: чем кончилась партия.
 * Вынесено отдельно, потому что в игре вдвоём эти надписи приходится
 * освежать и после показа плашки — друг может выйти из-за стола или
 * позвать на реванш уже тогда, когда итог на экране.
 */
function текстыИтога() {
  if (!партия) return { заголовок: '', пояснение: '' };
  /* За столом компанией дурака зовут по имени, а в парной игре дурак —
     не человек, а пара. Слово «соперник» там не годится: соперников
     было пятеро, и надо сказать, кто именно остался с картами.
     Прерванная связь — про нас самих, и рассказывается одинаково. */
  if (этоКомпания() && партия.результат !== 'связь-потеряна') {
    return текстыИтогаКомпании();
  }
  if (партия.результат === 'бот') {
    return {
      заголовок: 'Вы выиграли!',
      пояснение: 'Соперник остался с картами — он и есть дурак.'
    };
  }
  if (партия.результат === 'человек') {
    return {
      заголовок: 'Вы проиграли',
      пояснение: 'Вы остались с картами — на этот раз дурак вы.'
    };
  }
  if (партия.результат === 'друг-ушёл') {
    // Никого не обвиняем: чаще всего у друга просто пропала связь.
    return {
      заголовок: 'Друг вышел из игры',
      пояснение: 'Партия прервалась на середине — возможно, у друга пропала связь. ' +
                 'Дурака в такой партии нет.'
    };
  }
  if (партия.результат === 'связь-потеряна') {
    // Человек не виноват: у него пропал интернет, и партия закрылась без него.
    return {
      заголовок: 'Партия прервалась',
      пояснение: 'Связь пропадала слишком долго, и игра закончилась без вас. ' +
                 'Дурака в такой партии нет — вернитесь в меню и начните новую игру.'
    };
  }
  return { заголовок: 'Ничья', пояснение: 'Карты кончились у обоих — дурака нет.' };
}

/** Имена тех, кто остался дураком. Про себя пишем «вы», а не своё имя. */
function именаДураков() {
  const имена = [];
  for (const место of местаКомпании() || []) {
    if (место.проиграл) имена.push(место.этоЯ ? 'вы' : место.имя);
  }
  return имена;
}

/** Чем кончилась партия компанией: кто дурак, а в парной игре — какая пара. */
function текстыИтогаКомпании() {
  if (партия.результат === 'друг-ушёл') {
    return {
      заголовок: 'Партия прервалась',
      пояснение: 'За столом не осталось соперников — дурака в этой партии нет.'
    };
  }
  const дураки = именаДураков();
  if (дураки.length === 0) {
    // Ничья бывает, когда карты кончились у всех разом.
    return {
      заголовок: партия.результат === 'ничья' ? 'Ничья' : 'Партия окончена',
      пояснение: 'Карты кончились у всех разом — дурака нет.'
    };
  }

  const яДурак = дураки.indexOf('вы') !== -1;
  const списком = дураки.join(' и ');
  if (партия.парами) {
    // Дурак в парной игре — не человек, а пара: проигрывают оба сразу.
    return яДурак
      ? { заголовок: 'Ваша пара проиграла',
          пояснение: 'Дураки — ' + списком + '. В игре парами проигрывают вдвоём.' }
      : { заголовок: 'Ваша пара выиграла!',
          пояснение: 'Проиграла пара: ' + списком + '.' };
  }
  return яДурак
    ? { заголовок: 'Вы проиграли',
        пояснение: 'Вы остались с картами — на этот раз дурак вы.' }
    : { заголовок: 'Вы выиграли!',
        пояснение: 'Дурак — ' + списком + ': карты остались у него.' };
}

/**
 * Написать заголовок итога и подпись под ним. В игре вдвоём к подписи
 * добавляется вторая фраза — что делать дальше. Такие объяснения занимают
 * две-три строки, и в рамку для короткой строки «Побед подряд: 3» им нельзя:
 * там они кричат громче самого заголовка.
 */
function обновитьТекстыИтога() {
  const тексты = текстыИтога();
  const хвост = этоСетеваяИгра() && подсказкаПослеПартии ? ' ' + подсказкаПослеПартии : '';
  написать('текст-результата', тексты.заголовок);
  написать('пояснение-результата', тексты.пояснение + хвост);
}

function показатьРезультат() {
  таймерИтога = null;
  // За паузу перед показом всё могло измениться, поэтому проверяем заново:
  // партия есть, она действительно доиграна, человек стоит у стола и не занят
  // вопросом «точно выйти?». Иначе плашка легла бы поверх чужого экрана
  // и перекрыла бы кнопки.
  if (!партия || !партия.завершена) return;
  if (!этоЭкранИгры() || ждёмОтветПроВыход) return;
  обновитьТекстыИтога();
  // В игре вдвоём эта же кнопка предлагает не новую партию с ботом,
  // а реванш в той же комнате — с тем же другом и тем же кодом.
  написать('кнопка-ещё', этоСетеваяИгра() ? 'Ещё партию' : 'Играть ещё');
  показатьЭлемент('кнопка-ещё', реваншВозможен());
  показатьПлашкуИтога();
}

/* ---------------------------------------------------------------------
   Действия человека
   --------------------------------------------------------------------- */

/**
 * Положить карту в атаку. Развилка по режиму стоит здесь, а не в обработчике
 * нажатия: проверки «можно ли так ходить» и подсветка карт для обоих режимов
 * одни и те же, различается только последний шаг — свой стол или сервер.
 */
function сходитьКартой(индекс) {
  if (этоСетеваяИгра()) {
    отправитьХодНаСервер({ действие: 'ходить', карта: индекс });
    return;
  }
  const карта = партия.руки.человек[индекс];
  const перваяВПодходе = партия.стол.length === 0;
  if (!положитьВАтаку(партия, 'человек', индекс)) return;
  /* Свой ход называем вслух наравне с чужим. Раньше про ход человека
     не говорилось ничего, и после отбоя последней карты стол успевал
     опустеть быстрее, чем игрок переводил на него взгляд: он видел
     только «Соперник сказал Бито» и не понимал, куда делся его ход. */
  /* Ждать под это сообщение бот не обязан: положенная карта остаётся лежать
     на столе, её видно и без паузы. Поэтому темп здесь прежний. */
  показатьСобытие((перваяВПодходе ? 'Вы сходили ' : 'Вы подкинули ') + названиеКарты(карта),
                  ПОКАЗ_СОБЫТИЯ, ЗАДЕРЖКА_БОТА);
  звукКарты();
  выбраннаяКарта = null;
  продолжить();
}

/** Отбить карту на столе. Та же развилка: свой стол либо сервер. */
function отбитьсяКартой(индексПары, индексКарты) {
  if (этоСетеваяИгра()) {
    отправитьХодНаСервер({ действие: 'отбить', пара: индексПары, карта: индексКарты });
    return true;
  }
  // Названия берём до хода: после него карта уже уехала из руки на стол.
  const пара = партия.стол[индексПары];
  const атака = пара ? пара.атака : null;
  const карта = партия.руки.человек[индексКарты];
  if (!отбить(партия, индексПары, индексКарты)) return false;
  /* Отбились последней неотбитой картой — соперник вот-вот скажет «Бито»
     и стол уедет. Только в этом случае просим бота подождать подольше. */
  const столЗакрыт = неотбитых(партия) === 0;
  показатьСобытие('Вы отбили ' + названиеКарты(атака) + ' картой ' + названиеКарты(карта),
                  ПОКАЗ_СОБЫТИЯ, столЗакрыт ? ПАУЗА_ПОСЛЕ_СВОЕГО_ОТБОЯ : ЗАДЕРЖКА_БОТА);
  звукКарты();
  выбраннаяКарта = null;
  продолжить();
  return true;
}

function тапПоКартеЧеловека(индекс) {
  if (!партия || партия.завершена || ждёмОтветПроВыход) return;
  /* Только что нажали кнопку — это касание может оказаться её же «хвостом»
     (подробности и замеры — у ГЛУХОТА_ПОСЛЕ_КНОПКИ).
     Молчим здесь нарочно: отвечать вспышкой и звуком на палец, который
     ничего не нажимал, значит ругать человека за то, чего он не делал.
     Проверка стоит раньше «не ваш ход» ещё и поэтому: после «Беру» слово
     уходит сопернику, и хвост касания получил бы отказ «сейчас ходит
     соперник» — прямо в ответ на удачно нажатую кнопку. */
  if (Date.now() < рукаГлухаДо) return;
  if (ждёмОтветаНаХод()) {
    отказатьСловами(ТЕКСТ_ХОД_ЛЕТИТ);
    return;
  }
  /* Бот думает от 0,7 до 3 секунд и делает несколько ходов подряд — за это
     время нетерпеливый игрок успевает потыкать в свои карты. Раньше игра
     на это молчала, и человек решал, что нажатие не дошло. */
  if (!сейчасМойХод()) {
    отказатьПоКарте(индекс, текстНеВашХод());
    return;
  }
  const карта = партия.руки.человек[индекс];
  if (!карта) return;
  const текущая = фаза(партия);
  /* Прошлую новость здесь больше не стираем. Раньше она гасла на любом
     касании руки — в том числе когда человек просто поднимал карту, чтобы
     выбрать, что ею бить: сообщение о чужом ходе исчезало ни за что.
     Свой ход заменит её сам, сразу же и своим текстом. */

  if (текущая === 'атака' || текущая === 'подкидывание' || текущая === 'докидывание') {
    if (!можноПоложить(партия, карта)) {
      отказатьПоКарте(индекс, текущая === 'атака'
        ? 'Сейчас этой картой ходить нельзя'
        : 'Нужна карта того же достоинства');
      return;
    }
    сходитьКартой(индекс);
    return;
  }

  if (текущая === 'защита') {
    // Ищем, какие карты на столе эта карта вообще может побить.
    const цели = [];
    партия.стол.forEach(function (пара, i) {
      if (!пара.защита && бьёт(карта, пара.атака, партия.козырь)) цели.push(i);
    });
    // В переводном той же картой можно не крыть, а перевести ход дальше.
    const переводом = можноПеревестиЭтой(карта);
    if (цели.length === 0 && !переводом) {
      отказатьПоКарте(индекс, 'Этой картой не отбиться');
      return;
    }
    if (цели.length === 1 && !переводом) {
      // Крыть нечего выбирать — сразу бьём единственную подходящую карту.
      отбитьсяКартой(цели[0], индекс);
      return;
    }
    // Выбор есть (несколько целей или перевод) — карту только поднимаем,
    // а решает человек: за него такое не решают.
    выбраннаяКарта = (выбраннаяКарта === индекс) ? null : индекс;
    перерисовать();
  }
}

function тапПоПаре(индексПары) {
  if (!партия || партия.завершена || ждёмОтветПроВыход) return;
  if (ждёмОтветаНаХод()) {
    отказатьСловами(ТЕКСТ_ХОД_ЛЕТИТ);
    return;
  }
  if (!сейчасМойХод()) {
    отказатьСловами(текстНеВашХод());
    return;
  }
  // Ход наш, но мы не отбиваемся: по столу бить нечем, карта идёт из руки.
  if (фаза(партия) !== 'защита') {
    отказатьСловами('Играйте картой из своей руки');
    return;
  }
  /* Порядок тут не всем очевиден: сначала поднять свою карту, потом указать,
     что ею бьёшь. Новичок делает наоборот — тычет в карту соперника. */
  if (выбраннаяКарта === null) {
    отказатьСловами('Сначала выберите карту в своей руке');
    return;
  }
  отбитьсяКартой(индексПары, выбраннаяКарта);
}

/**
 * Нажатие по стопке колоды. Брать из неё руками нельзя — карты добираются
 * сами в конце подхода, но об этом нигде не сказано, и новичок тыкает
 * в стопку, ожидая объяснения. Теперь оно приходит.
 */
function тапПоКолоде() {
  if (!партия || партия.завершена || ждёмОтветПроВыход) return;
  const осталось = партия.колода.length;
  отказатьСловами(осталось > 0
    ? 'В колоде ' + осталось + ' ' + словоКарты(осталось) + ' — карты добираются сами'
    : 'Колода пуста — добирать больше нечего');
}

/**
 * Нажатие по подписи «Козырь ♣». В разметке она лежит не внутри блока колоды,
 * а рядом с ним, поэтому нажатие на неё приходится ловить отдельно — на вид
 * же это тот самый угол с колодой, и человек тычет туда наравне со стопкой.
 * Отвечаем главным правилом игры: новичок как раз не понимает, почему одни
 * карты подсвечены как «можно», а козырная бьёт что угодно.
 */
function тапПоКозырю() {
  if (!партия || партия.завершена || ждёмОтветПроВыход) return;
  /* Слово «козырь» один раз, а не два: строка подсказки показывает это
     сообщение вместе с напоминанием о действии через « · », а места там
     около 90 знаков на двоих — что не влезло, обрежется на полуслове.
     Масть в сетевой партии приходит от сервера и может оказаться пустой:
     тогда говорим то же самое без неё, иначе получится «Козырь  бьёт»
     с дырой посередине. */
  отказатьСловами(партия.козырь
    ? 'Козырь ' + партия.козырь + ' бьёт любую карту другой масти'
    : 'Козырь бьёт любую карту другой масти');
}

function нажатьБито() {
  if (!партия || партия.завершена || ждёмОтветПроВыход) return;
  const текущая = фаза(партия);
  if (!мнеМожноЗакончитьПодход(текущая)) return;
  рукаГлухаДо = Date.now() + ГЛУХОТА_ПОСЛЕ_КНОПКИ;
  if (этоСетеваяИгра()) {
    // Рассказ о конце подхода в сети придёт от сервера — своего не сочиняем,
    // иначе у двух игроков будут разные версии одного события.
    отправитьХодНаСервер({ действие: 'бито' });
    return;
  }
  // Карты и руку запоминаем до завершения: после него стол уже пуст,
  // а рука выросла — только по разнице и видно, сколько пришло из колоды.
  const заберёт = партия.берёт;
  const защитник = защищается(партия);
  const карты = картыСоСтола();
  const былоВРуке = партия.руки.человек.length;
  завершитьПодход(партия);
  const взятоСоСтола = заберёт && защитник === 'человек' ? карты.length : 0;
  показатьСобытие(текстКонцаПодхода(карты, заберёт, защитник,
                                    сколькоДобрали(былоВРуке, взятоСоСтола)),
                  ПОКАЗ_СОБЫТИЯ, ПАУЗА_ПОСЛЕ_ПОДХОДА);
  if (заберёт) звукВзятия(); else звукКарты();
  выбраннаяКарта = null;
  продолжить();
}

function нажатьБеру() {
  if (!партия || партия.завершена || ждёмОтветПроВыход) return;
  if (фаза(партия) !== 'защита' || !сейчасМойХод()) return;
  рукаГлухаДо = Date.now() + ГЛУХОТА_ПОСЛЕ_КНОПКИ;
  if (этоСетеваяИгра()) {
    отправитьХодНаСервер({ действие: 'беру' });
    return;
  }
  объявитьБеру(партия);
  /* Раньше здесь было «Вы берёте карты», а строка действия рядом писала
     «Вы забираете карты. Соперник может подкинуть…» — одно и то же дважды
     в одной строке. Пока событие гасло за три секунды, это было незаметно;
     теперь оно висит до следующего хода, и повтор бросался бы в глаза.
     Оставляем короткое подтверждение нажатия, а что будет дальше,
     рассказывает строка действия. Сколько карт забрали и какие именно —
     скажет сообщение в конце подхода, когда они и вправду уедут в руку. */
  показатьСобытие('Вы сказали «Беру»', ПОКАЗ_СОБЫТИЯ, ПАУЗА_ПОД_СОБЫТИЕ);
  звукВзятия();
  выбраннаяКарта = null;
  продолжить();
}

/**
 * «Перевести» — вместо того, чтобы крыть, кладём на стол свою карту того же
 * достоинства, и отбиваться приходится следующему. Кнопка работает с той
 * картой, которую человек поднял: другой она не переведёт.
 */
function нажатьПеревести() {
  if (!партия || партия.завершена || ждёмОтветПроВыход) return;
  if (фаза(партия) !== 'защита' || !сейчасМойХод()) return;
  const индекс = выбраннаяКарта;
  if (индекс === null) return;
  const карта = партия.руки.человек[индекс];
  if (!можноПеревестиЭтой(карта)) return;
  рукаГлухаДо = Date.now() + ГЛУХОТА_ПОСЛЕ_КНОПКИ;
  if (этоСетеваяИгра()) {
    отправитьХодНаСервер({ действие: 'перевести', карта: индекс });
    return;
  }
  if (!перевести(партия, индекс)) return;
  показатьСобытие('Вы перевели ход картой ' + названиеКарты(карта),
                  ПОКАЗ_СОБЫТИЯ, ПАУЗА_ПОД_СОБЫТИЕ);
  звукКарты();
  выбраннаяКарта = null;
  продолжить();
}

/** Почему партия начинается именно с этого игрока — иначе первый ход выглядит случайным. */
function текстКтоПервый() {
  const мой = младшийКозырь(партия, 'человек');
  const чужой = младшийКозырь(партия, 'бот');
  if (партия.атакует === 'человек') {
    if (мой && чужой) return 'У вас младший козырь ' + названиеКарты(мой) + ' — вы ходите первым';
    if (мой) return 'Козырь только у вас (' + названиеКарты(мой) + ') — вы ходите первым';
    return 'Козырей нет ни у кого — первым ходите вы';
  }
  // Карту бота не показываем: это его закрытая рука.
  return чужой && мой
    ? 'Младший козырь у соперника — он первый'
    : 'Козырь только у соперника — он первый';
}

/** Новая партия с нуля: старые таймеры гасим, всё состояние создаём заново. */
function начатьПартию() {
  if (таймер !== null) {
    clearTimeout(таймер);
    таймер = null;
  }
  отменитьПоказИтога();   // итог прошлой партии новой уже не касается
  убратьСобытие();
  выбраннаяКарта = null;
  итогЗасчитан = false;
  ждёмОтветПроВыход = false;
  /* Не обнуляем, а наоборот заводим окно: новую партию начинают кнопкой,
     и первые доли секунды рука не должна принимать «хвост» этого нажатия —
     иначе первый ход партии может сделаться сам. Начало партии — как раз
     то место, где эти доли секунды никому не мешают. */
  рукаГлухаДо = Date.now() + ГЛУХОТА_ПОСЛЕ_КНОПКИ;
  // Обычная партия всегда против бота: если до этого играли с другом,
  // сетевой режим здесь заканчивается.
  оставитьСетевуюПартию();
  режим = РЕЖИМ_БОТ;
  партия = создатьПартию(сложность);   // соперник тот, что выбран в меню
  показатьЭкран('экран-игры');
  подобратьРазмерКарты();
  показатьСобытие(текстКтоПервый(), ПОКАЗ_НАЧАЛА);
  продолжить();
}

/**
 * Чем обернётся выход — три разных случая, и путать их нельзя.
 *
 * За общим столом на троих и больше партия не прерывается: сервер сажает
 * на освободившееся место бота, и он доигрывает нашими картами, а остальные
 * играют дальше. Прежняя надпись обещала одинокого друга за столом — при
 * пятерых соперниках это была прямая неправда.
 */
function подписьВыхода() {
  if (этоКомпания()) {
    return 'Вы выйдете из партии — ваши карты доиграет бот, остальные продолжат.';
  }
  // Вдвоём уход — это не только своя брошенная партия: друг останется
  // за столом один и должен понять, почему.
  if (этоСетеваяИгра()) return 'Партия прервётся, друг останется за столом один.';
  return 'Партия прервётся, результат не запишется.';
}

/**
 * Спросить, точно ли выходить. Пока висит вопрос, партия стоит на паузе:
 * отложенный ход соперника гасим, чтобы за время раздумий ничего не менялось.
 */
function спроситьПроВыход() {
  // Партия уже доиграна (итог засчитан) — терять нечего, спрашивать не о чем.
  if (!партия || партия.завершена) { выйтиВМеню(); return; }
  if (таймер !== null) {
    clearTimeout(таймер);
    таймер = null;
  }
  ждёмОтветПроВыход = true;
  написать('подпись-выхода', подписьВыхода());
  const плашка = эл('экран-выхода');
  if (!плашка) { выйтиВМеню(); return; }   // нет плашки — выходим сразу, как раньше
  плашка.classList.add('экран--поверх');
  плашка.classList.add('экран--виден');
}

/** «Продолжить партию»: убираем вопрос и возвращаем игру в ход. */
function остатьсяВПартии() {
  ждёмОтветПроВыход = false;
  /* Здесь окно глухоты нужнее, чем у кнопок нижней панели. Плашка выхода
     прижата к низу, и «Продолжить партию» идёт во всю ширину как раз там,
     где лежит рука. Плашка пропадает мгновенно, рука перерисовывается
     тут же — и второе касание того же пальца попадает уже в карту, которая
     улетает на стол без возможности отменить. Внизу под кнопкой панели
     такое касание принимает на себя сама панель, а здесь принимать некому. */
  рукаГлухаДо = Date.now() + ГЛУХОТА_ПОСЛЕ_КНОПКИ;
  const плашка = эл('экран-выхода');
  if (плашка) {
    плашка.classList.remove('экран--виден');
    плашка.classList.remove('экран--поверх');
  }
  // Пока человек думал над выходом, партия вдвоём могла закончиться:
  // плашку итога тогда придержали, чтобы она не легла поверх вопроса.
  // Вопрос убран — показываем итог сейчас.
  if (партия && партия.завершена) { показатьРезультат(); return; }
  if (партия) продолжить();
}

/** Бросить партию и вернуться в меню — чтобы не спасаться перезагрузкой страницы. */
function выйтиВМеню() {
  ждёмОтветПроВыход = false;
  if (таймер !== null) {
    clearTimeout(таймер);
    таймер = null;
  }
  отменитьПоказИтога();
  убратьСобытие();
  выбраннаяКарта = null;
  // Друга предупреждаем до того, как забудем партию: иначе он будет ждать
  // ходов от игрока, который уже ушёл.
  оставитьСетевуюПартию();
  режим = РЕЖИМ_БОТ;
  партия = null;
  показатьЭкран('экран-меню');
}

