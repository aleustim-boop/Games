/* =====================================================================
   ЧАСТЬ 4. ИГРА ВДВОЁМ: МОСТ К СЕРВЕРУ

   Здесь нет ни правил, ни сети. Правила в игре вдвоём считает сервер,
   с сервером разговаривает js/сеть.js, а этот кусок делает одно:
   превращает присланное сервером состояние в такой же объект партии,
   какой игра рисует всю дорогу. Поэтому стол, веер карт, подсветка
   «можно/нельзя» и два ряда при большой руке работают в сетевой игре
   сами собой — ни одна строка отрисовки под сеть не переписана.

   Чего здесь нарочно нет: своей проверки ходов. Клиент может ошибиться
   или отстать от жизни, поэтому последнее слово всегда за сервером —
   он и присылает то состояние, которое мы показываем.
   ===================================================================== */

const РЕЖИМ_БОТ = 'бот';
const РЕЖИМ_СЕТЬ = 'сеть';

let режим = РЕЖИМ_БОТ;          // с кем идёт партия прямо сейчас
let ждёмОтветСервера = false;   // ход отправлен, ответа ещё нет
let номерПоказанногоСобытия = 0;
let сетьПредупредилаОРазладе = false;
let другУшёлИзПартии = false;   // за столом больше некого звать на реванш
let насВывелиИзПартии = false;  // сервер счёл нас пропавшими и закрыл партию без нас
/* Вторая фраза под заголовком итога в игре вдвоём: что произошло с другом
   и что делать дальше. Держим её отдельной строкой, потому что заголовок
   с объяснением пишутся в одном месте, а новости от сервера приходят в другом
   и позже — иногда уже после того, как плашка итога легла на экран. */
let подсказкаПослеПартии = '';

/** Идёт ли сейчас партия с живым другом. */
function этоСетеваяИгра() {
  return режим === РЕЖИМ_СЕТЬ;
}

/**
 * Есть ли смысл показывать кнопку «Ещё партию». Звать на реванш некого
 * в двух случаях: друг ушёл из-за стола или сервер вывел из партии нас самих
 * (пропал интернет). В обоих сервер отвечает на кнопку отказом, а отказ
 * попадает в строку подсказки, закрытую плашкой итога, — для человека это
 * выглядит сломанной кнопкой. Поэтому кнопку убираем совсем.
 * В одиночной игре кнопка «Играть ещё» видна всегда.
 */
function реваншВозможен() {
  return !этоСетеваяИгра() || (!другУшёлИзПартии && !насВывелиИзПартии);
}

/**
 * Подключён ли файл js/сеть.js. Игра работает и без него — просто
 * остаётся одиночной, а кнопка «Играть с другом» ничего не откроет.
 */
function естьСеть() {
  return typeof window !== 'undefined' && window.Сеть &&
         typeof window.Сеть.отправитьХод === 'function';
}

/** Сказать серверу, что мы уходим, и погасить опрос. Вне сетевой партии — пустое действие. */
function оставитьСетевуюПартию() {
  // Хвосты прошлой сетевой партии не должны достаться игре с ботом:
  // иначе там останется надпись «Отправляем ход…» или спрятанная кнопка.
  ждёмОтветСервера = false;
  другУшёлИзПартии = false;
  насВывелиИзПартии = false;
  подсказкаПослеПартии = '';
  показатьСвязь('');
  if (!этоСетеваяИгра() || !естьСеть()) return;
  if (typeof window.Сеть.покинутьПартию === 'function') window.Сеть.покинутьПартию();
}

/**
 * Отправить намерение на сервер. Своё состояние не меняем совсем:
 * пока сервер не ответил, на столе всё по-старому. Так две игры
 * не расходятся: у обоих игроков стол всегда такой, каким его видит сервер.
 */
function отправитьХодНаСервер(намерение) {
  if (!естьСеть()) {
    показатьСобытие('Связи с игрой нет — ход не отправлен');
    return null;
  }
  выбраннаяКарта = null;
  if (ждёмОтветСервера) return null;   // второй тап, пока летит первый
  ждёмОтветСервера = true;
  // Пока ход летит, человек видит «Отправляем ход…»: на медленной связи
  // ответа ждать до десяти секунд, и молчащий экран выглядит зависшим.
  нарисоватьСтрокуСвязи();
  перерисовать();

  return window.Сеть.отправитьХод(намерение).then(function (ответ) {
    перестатьЖдатьОтвет();
    // Состояние из ответа применит сам js/сеть.js — дверь одна.
    if (!ответ || ответ.ошибкаСвязи) return null;   // про связь расскажет строка связи
    if (!ответ.принято && ответ.причина) показатьСобытие(ответ.причина);
    if (партия) перерисовать();
    return ответ;
  }, function () {
    // Ответа не будет совсем. Ожидание всё равно надо снять, иначе игра
    // так и останется «отправляющей ход» и перестанет принимать нажатия.
    перестатьЖдатьОтвет();
    return null;
  });
}

/** Ответ пришёл (или уже не придёт): снимаем ожидание и возвращаем строку связи. */
function перестатьЖдатьОтвет() {
  ждёмОтветСервера = false;
  нарисоватьСтрокуСвязи();
}

/**
 * Кнопка на экране итога. В одиночной игре это новая партия с ботом,
 * в игре вдвоём — предложение сыграть ещё в той же комнате: код и место
 * за столом остаются прежними, карты раздаются заново.
 */
function нажатьЕщёПартию() {
  if (этоСетеваяИгра()) {
    const ответСервера = отправитьХодНаСервер({ действие: 'ещё' });
    // Обещать реванш заранее нельзя: сервер может и отказать (друг уже вышел).
    // Пишем «ждём друга» только после того, как предложение принято.
    if (ответСервера) ответСервера.then(function (ответ) {
      if (ответ && ответ.принято) показатьКонцовку(мыПозвалиНаРеванш());
    });
    return;
  }
  начатьПартию();
}

/* ---------------------------------------------------------------------
   Превращение ответа сервера в привычный объект партии
   --------------------------------------------------------------------- */

/**
 * Карта-невидимка. Такими заполняются чужая рука и колода: игре для
 * отрисовки нужна только их длина, а настоящих карт соперника у нас нет
 * и быть не должно — сервер их не присылает.
 */
function картаНевидимка() {
  return { масть: '', имя: '', вес: 0 };
}

function рядНевидимок(сколько) {
  const ряд = [];
  for (let i = 0; i < сколько; i++) ряд.push(картаНевидимка());
  return ряд;
}

/** Сервер говорит про итог глазами игрока, а игра хранит, кто остался дураком. */
function результатИзИтога(итог) {
  if (итог === 'победа') return 'бот';        // дурак — соперник
  if (итог === 'поражение') return 'человек'; // дурак — я
  if (итог === 'ничья') return 'ничья';
  // Партия оборвалась не по картам: друг ушёл. Дурака в ней нет, и выдавать
  // это за ничью нельзя — карты на руках остались у обоих.
  if (итог === 'соперник-ушёл') return 'друг-ушёл';
  return null;
}

/**
 * Чем кончилась партия вдвоём. Обычные исходы разбирает результатИзИтога,
 * а здесь ловится случай, которого там нет: партия закрыта, а итога сервер
 * не прислал вовсе.
 *
 * Так бывает, когда пропавшим сервер считает нас самих: интернет отвалился
 * на несколько минут (метро, лифт), сервер вывел нас из партии, а когда мы
 * вернулись — партии уже нет. Победы, поражения и «друг ушёл» тут не было,
 * поэтому нужен свой отдельный итог. Без него игра показывала «Ничья.
 * Карты кончились у обоих», хотя карты оставались на руках у обоих.
 */
function результатСетевойПартии(вид) {
  const результат = результатИзИтога(вид.итог);
  if (результат) return результат;
  return вид.завершена ? 'связь-потеряна' : null;
}

/** Целое число из ответа сервера, без сюрпризов вроде null и «пять». */
function целоеИзОтвета(значение) {
  const число = Number(значение);
  return Number.isFinite(число) && число > 0 ? Math.floor(число) : 0;
}

/**
 * Собрать объект партии из того, что прислал сервер. Форма — ровно та же,
 * что у обычной партии против бота, поэтому дальше игра ничего не замечает.
 */
function партияИзВида(вид) {
  const стол = Array.isArray(вид.стол) ? вид.стол.map(function (пара) {
    return { атака: пара.атака, защита: пара.защита || null };
  }) : [];

  return {
    сложность: СЛОЖНОСТЬ_ПО_УМОЛЧАНИЮ,   // за столом живой человек, уровня у него нет
    // Круг из двух мест: за столом мы и друг. Поля те же, что у обычной партии,
    // иначе правила (например, «кто отбивается») не смогут её прочитать.
    игроки: ['человек', 'бот'],
    выбывшие: [],
    пасы: [],
    размерКолоды: КОЛОДА_36,
    колода: рядНевидимок(целоеИзОтвета(вид.вКолоде)),
    козырь: вид.козырь || '',
    козырнаяКарта: вид.козырнаяКарта || null,
    руки: {
      человек: Array.isArray(вид.мояРука) ? вид.мояРука.slice() : [],
      бот: рядНевидимок(целоеИзОтвета(вид.картУСоперника))
    },
    стол: стол,
    отбой: [],            // сколько карт в отбое, экран не показывает
    атакует: вид.яАтакую ? 'человек' : 'бот',
    берёт: Boolean(вид.берут),
    завершена: Boolean(вид.завершена),
    результат: результатСетевойПартии(вид)
  };
}

/**
 * Сверка на всякий случай: игра считает очередь хода сама (по столу),
 * сервер присылает её отдельным полем. Если они разошлись — виновата
 * не отрисовка, а расхождение правил, и это надо увидеть сразу.
 * Ругаемся один раз за партию, чтобы не залить консоль.
 */
function сверитьОчередьХода(вид) {
  const поНашему = ктоХодит(партия) === 'человек';
  if (Boolean(вид.яХожу) === поНашему || вид.завершена || сетьПредупредилаОРазладе) return;
  сетьПредупредилаОРазладе = true;
  console.warn('Игра вдвоём: сервер и игра по-разному считают, чей сейчас ход. ' +
               'Показываем то, что сказал сервер.');
}

