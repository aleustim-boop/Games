/* =====================================================================
   Подкидной дурак — правила партии и отрисовка стола.

   Файл намеренно разделён на две части:
     ЧАСТЬ 1 «Правила» — работают только с объектом состояния «партия»,
             про экран и про кнопки ничего не знают. Их можно прогнать
             без браузера (автотест «бот против бота»);
     ЧАСТЬ 2 «Экран»  — по состоянию партии рисует картинку целиком,
             своих правил не придумывает.

   Разделение нужно, чтобы ошибку было видно сразу: если карта ушла
   не туда — это часть 1, если карта не там нарисовалась — часть 2.
   ===================================================================== */

'use strict';

/* =====================================================================
   ЧАСТЬ 1. ПРАВИЛА ПАРТИИ
   ===================================================================== */

// Масти и достоинства колоды из 36 карт (от шестёрки до туза).
const МАСТИ = ['♠', '♥', '♦', '♣']; // пики, черви, бубны, трефы
const КРАСНЫЕ_МАСТИ = ['♥', '♦'];
const ДОСТОИНСТВА = ['6', '7', '8', '9', '10', 'В', 'Д', 'К', 'Т'];

const КАРТ_В_РУКЕ = 6;          // до скольки карт добирают из колоды
const МАКС_КАРТ_В_ПОДХОДЕ = 6;  // больше шести карт за один подход не кладут

// Уровни соперника. Эти же слова показываются в меню и попадают в таблицу рекордов.
const СЛОЖНОСТИ = ['лёгкий', 'обычный', 'сложный'];
const СЛОЖНОСТЬ_ПО_УМОЛЧАНИЮ = 'обычный';

/** Незнакомое слово превращаем в «обычный», чтобы игра не зависела от опечатки. */
function проверитьСложность(значение) {
  return СЛОЖНОСТИ.indexOf(значение) !== -1 ? значение : СЛОЖНОСТЬ_ПО_УМОЛЧАНИЮ;
}

/**
 * Собрать полную колоду. Вес — число от 6 до 14, по нему сравниваем карты:
 * так не нужно каждый раз искать достоинство в списке.
 */
function собратьКолоду() {
  const колода = [];
  for (const масть of МАСТИ) {
    for (let i = 0; i < ДОСТОИНСТВА.length; i++) {
      колода.push({ масть: масть, имя: ДОСТОИНСТВА[i], вес: i + 6 });
    }
  }
  return колода;
}

/** Перетасовать колоду (алгоритм Фишера — Йетса, честное перемешивание). */
function перемешать(колода) {
  for (let i = колода.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const временно = колода[i];
    колода[i] = колода[j];
    колода[j] = временно;
  }
  return колода;
}

/**
 * Карты в руке держим по порядку: сначала некозырные по мастям,
 * козыри — в конце. Нужно только для удобства человека, на правила не влияет.
 */
function упорядочитьРуку(партия, игрок) {
  партия.руки[игрок].sort(function (а, б) {
    const аКозырь = а.масть === партия.козырь;
    const бКозырь = б.масть === партия.козырь;
    if (аКозырь !== бКозырь) return аКозырь ? 1 : -1;
    if (а.масть !== б.масть) return МАСТИ.indexOf(а.масть) - МАСТИ.indexOf(б.масть);
    return а.вес - б.вес;
  });
}

/**
 * Новая партия: тасуем колоду, раздаём по 6 карт, козырь — последняя карта
 * колоды (она лежит под колодой и достаётся последней).
 */
function создатьПартию(сложность) {
  const колода = перемешать(собратьКолоду());
  const козырнаяКарта = колода[колода.length - 1];

  const партия = {
    сложность: проверитьСложность(сложность),   // каким соперником играет бот
    колода: колода,                 // колода[0] — верхняя карта, последняя — козырная
    козырь: козырнаяКарта.масть,
    козырнаяКарта: козырнаяКарта,
    руки: { человек: [], бот: [] },
    стол: [],                       // список пар { атака: карта, защита: карта или null }
    отбой: [],                      // сюда уходят отбитые карты
    атакует: 'человек',
    берёт: false,                   // защищающийся сказал «Беру»
    завершена: false,
    результат: null                 // 'человек' | 'бот' — кто остался дураком, либо 'ничья'
  };

  // Раздаём по одной карте по очереди, как в жизни.
  for (let i = 0; i < КАРТ_В_РУКЕ; i++) {
    партия.руки.человек.push(партия.колода.shift());
    партия.руки.бот.push(партия.колода.shift());
  }
  партия.атакует = ктоХодитПервым(партия);
  упорядочитьРуку(партия, 'человек');
  return партия;
}

/** Самый младший козырь в руке (или null, если козырей нет). */
function младшийКозырь(партия, игрок) {
  let младший = null;
  for (const карта of партия.руки[игрок]) {
    if (карта.масть !== партия.козырь) continue;
    if (младший === null || карта.вес < младший.вес) младший = карта;
  }
  return младший;
}

/** Первым ходит тот, у кого младший козырь. Козырей нет ни у кого — ходит человек. */
function ктоХодитПервым(партия) {
  const уЧеловека = младшийКозырь(партия, 'человек');
  const уБота = младшийКозырь(партия, 'бот');
  if (уЧеловека && уБота) return уЧеловека.вес < уБота.вес ? 'человек' : 'бот';
  if (уЧеловека) return 'человек';
  if (уБота) return 'бот';
  return 'человек';
}

/** Кто сейчас отбивается — тот, кто не атакует. */
function защищается(партия) {
  return партия.атакует === 'человек' ? 'бот' : 'человек';
}

/**
 * Что сейчас происходит за столом. Фазу не храним, а вычисляем по столу —
 * тогда её невозможно «забыть переключить» и получить зависание.
 *   'атака'       — стол пуст, атакующий должен положить карту;
 *   'защита'      — на столе есть неотбитая карта, ход защищающегося;
 *   'подкидывание'— всё отбито, атакующий может подкинуть или сказать «Бито»;
 *   'докидывание' — защищающийся берёт, атакующий может докинуть карты;
 *   'конец'       — партия окончена.
 */
function фаза(партия) {
  if (партия.завершена) return 'конец';
  if (партия.стол.length === 0) return 'атака';
  if (партия.берёт) return 'докидывание';
  for (const пара of партия.стол) {
    if (!пара.защита) return 'защита';
  }
  return 'подкидывание';
}

/** Чей сейчас ход: 'человек', 'бот' или null, если партия окончена. */
function ктоХодит(партия) {
  const текущая = фаза(партия);
  if (текущая === 'конец') return null;
  if (текущая === 'защита') return защищается(партия);
  return партия.атакует;
}

/** Бьёт ли карта «чем» карту «что»: старше той же масти либо козырь по некозырю. */
function бьёт(чем, что, козырь) {
  if (чем.масть === что.масть) return чем.вес > что.вес;
  return чем.масть === козырь && что.масть !== козырь;
}

/** Сколько карт на столе ещё не отбито. */
function неотбитых(партия) {
  let счёт = 0;
  for (const пара of партия.стол) if (!пара.защита) счёт++;
  return счёт;
}

/** Достоинства всех карт на столе — только ими разрешено подкидывать. */
function достоинстваНаСтоле(партия) {
  const список = [];
  for (const пара of партия.стол) {
    if (список.indexOf(пара.атака.имя) === -1) список.push(пара.атака.имя);
    if (пара.защита && список.indexOf(пара.защита.имя) === -1) список.push(пара.защита.имя);
  }
  return список;
}

/**
 * Можно ли сейчас положить эту карту в атаку.
 * Два ограничения: не больше шести карт за подход и не больше,
 * чем карт в руке у того, кто отбивается (иначе ему нечем крыть).
 */
function можноПоложить(партия, карта) {
  const текущая = фаза(партия);
  if (текущая !== 'атака' && текущая !== 'подкидывание' && текущая !== 'докидывание') return false;
  if (партия.стол.length >= МАКС_КАРТ_В_ПОДХОДЕ) return false;
  if (неотбитых(партия) >= партия.руки[защищается(партия)].length) return false;
  if (текущая === 'атака') return true;
  return достоинстваНаСтоле(партия).indexOf(карта.имя) !== -1;
}

/** Положить карту из руки в атаку. Возвращает true, если ход состоялся. */
function положитьВАтаку(партия, игрок, индексКарты) {
  if (игрок !== партия.атакует) return false;
  const карта = партия.руки[игрок][индексКарты];
  if (!карта || !можноПоложить(партия, карта)) return false;
  партия.руки[игрок].splice(индексКарты, 1);
  партия.стол.push({ атака: карта, защита: null });
  return true;
}

/** Отбить карту на столе. Возвращает true, если получилось. */
function отбить(партия, индексПары, индексКарты) {
  if (фаза(партия) !== 'защита') return false;
  const пара = партия.стол[индексПары];
  if (!пара || пара.защита) return false;
  const защитник = защищается(партия);
  const карта = партия.руки[защитник][индексКарты];
  if (!карта || !бьёт(карта, пара.атака, партия.козырь)) return false;
  пара.защита = карта;
  партия.руки[защитник].splice(индексКарты, 1);
  return true;
}

/** «Беру»: защищающийся отказался отбиваться, дальше атакующий может докинуть. */
function объявитьБеру(партия) {
  if (фаза(партия) !== 'защита') return false;
  партия.берёт = true;
  return true;
}

/** Добор из колоды до шести карт: сначала атакующий, потом защищающийся. */
function добрать(партия) {
  const очередь = [партия.атакует, защищается(партия)];
  for (const игрок of очередь) {
    while (партия.руки[игрок].length < КАРТ_В_РУКЕ && партия.колода.length > 0) {
      партия.руки[игрок].push(партия.колода.shift());
    }
  }
}

/**
 * Партия кончается, когда колода пуста и хотя бы у одного игрока нет карт.
 * Кто остался с картами — дурак; вышли оба — ничья.
 */
function проверитьКонец(партия) {
  if (партия.колода.length > 0) return;
  const человекПуст = партия.руки.человек.length === 0;
  const ботПуст = партия.руки.бот.length === 0;
  if (!человекПуст && !ботПуст) return;
  партия.завершена = true;
  if (человекПуст && ботПуст) партия.результат = 'ничья';
  else партия.результат = человекПуст ? 'бот' : 'человек';
}

/**
 * Закончить подход: карты со стола уходят в отбой либо к тому, кто берёт;
 * затем добор и передача хода. Если защищающийся отбился — атакует он.
 */
function завершитьПодход(партия) {
  if (партия.завершена) return false;
  const защитник = защищается(партия);
  const защитникВзял = партия.берёт;

  for (const пара of партия.стол) {
    if (защитникВзял) {
      партия.руки[защитник].push(пара.атака);
      if (пара.защита) партия.руки[защитник].push(пара.защита);
    } else {
      партия.отбой.push(пара.атака);
      if (пара.защита) партия.отбой.push(пара.защита);
    }
  }

  партия.стол = [];
  партия.берёт = false;
  добрать(партия);
  if (!защитникВзял) партия.атакует = защитник; // отбился — теперь ход его
  упорядочитьРуку(партия, 'человек');
  проверитьКонец(партия);
  return true;
}

/* ---------------------------------------------------------------------
   Бот. Три манеры игры — по выбранному уровню соперника:

   «обычный» — жадный расчёт: кроет самой мелкой подходящей картой,
               козырь придерживает, берёт, когда крыть нечем;
   «лёгкий»  — тот же бот, но время от времени ошибается, как новичок:
               бьёт козырем там, где хватило бы простой карты,
               и ходит случайной картой вместо самой мелкой;
   «сложный» — бережёт козыри всерьёз (за мелкую карту лучше возьмёт,
               чем потратит козырь), не отдаёт козыри тому, кто берёт,
               и помнит вышедшие карты: когда колода кончилась, он точно
               знает руку соперника и ходит тем, что тому не побить.
   --------------------------------------------------------------------- */

// Как часто лёгкий соперник играет не лучшей картой.
const ДОЛЯ_ОШИБОК_ЛЁГКОГО = 0.35;

/* Повадки сложного соперника подбирались замером — по 3000 партий против
   обычного бота на каждый вариант. Обычный выигрывает 40% партий; сложный
   со счётом карт и бережливостью к козырям — 49%, и ничьих вдвое меньше
   (10% против 21%). Ещё одну идею — «за мелкую карту лучше взять, чем крыть
   козырем» — замер отверг: с ней бот выигрывал только 38%, поэтому её тут нет. */

/** Из списка индексов руки выбрать индекс самой младшей карты. */
function индексМладшей(рука, индексы) {
  let лучший = индексы[0];
  for (const i of индексы) {
    if (рука[i].вес < рука[лучший].вес) лучший = i;
  }
  return лучший;
}

/** Из списка индексов руки выбрать индекс самой старшей карты. */
function индексСтаршей(рука, индексы) {
  let лучший = индексы[0];
  for (const i of индексы) {
    if (рука[i].вес > рука[лучший].вес) лучший = i;
  }
  return лучший;
}

/** Есть ли в руке ещё одна карта того же достоинства — такой картой хорошо ходить. */
function естьПара(рука, индекс) {
  for (let i = 0; i < рука.length; i++) {
    if (i !== индекс && рука[i].имя === рука[индекс].имя) return true;
  }
  return false;
}

/**
 * Какие карты могут быть у соперника. Считаем от обратного: вся колода
 * минус то, что бот видит своими глазами, — его рука, отбой и стол.
 * Пока в колоде есть карты, список получается «возможные», а когда
 * колода кончилась — это уже точная рука соперника.
 */
function возможныеКартыСоперника(партия, игрок) {
  const видно = Object.create(null);
  const пометить = function (карта) { видно[карта.имя + карта.масть] = true; };
  for (const карта of партия.руки[игрок]) пометить(карта);
  for (const карта of партия.отбой) пометить(карта);
  for (const пара of партия.стол) {
    пометить(пара.атака);
    if (пара.защита) пометить(пара.защита);
  }
  const остальные = [];
  for (const карта of собратьКолоду()) {
    if (!видно[карта.имя + карта.масть]) остальные.push(карта);
  }
  return остальные;
}

/** Может ли соперник побить эту карту хоть чем-нибудь из возможных. */
function соперникПобьёт(партия, карта, чужие) {
  for (const чужая of чужие) {
    if (бьёт(чужая, карта, партия.козырь)) return true;
  }
  return false;
}

/** Самая мелкая карта, но при равных — та, к которой в руке есть пара: её потом подкинем. */
function мелкаяСОглядкойНаПару(рука, выбор) {
  let лучший = выбор[0];
  let лучшаяОценка = Infinity;
  for (const i of выбор) {
    const оценка = рука[i].вес - (естьПара(рука, i) ? 0.5 : 0);
    if (оценка < лучшаяОценка) {
      лучшаяОценка = оценка;
      лучший = i;
    }
  }
  return лучший;
}

/**
 * Чем ходит сложный соперник. Вернёт -1, если решил закончить подход.
 * Главная его сила — в концовке: когда колода пуста, он по отбою и по своей
 * руке точно знает карты соперника и кладёт то, что тому нечем крыть.
 */
function выборСложного(партия, игрок, годные, первыйХод) {
  const рука = партия.руки[игрок];
  const эндшпиль = партия.колода.length === 0;

  if (эндшпиль) {
    const чужие = возможныеКартыСоперника(партия, игрок);
    // Карта, которую сопернику нечем побить, — он вынужден будет взять.
    // Козырь здесь тоже в дело: в концовке он важнее бережливости.
    const неотбиваемые = годные.filter(function (i) {
      return !соперникПобьёт(партия, рука[i], чужие);
    });
    if (неотбиваемые.length > 0) return индексМладшей(рука, неотбиваемые);
    // Соперник и так берёт, а колоды больше нет: сбрасываем всё, чтобы
    // остаться с пустыми руками — это и есть победа.
    if (партия.берёт) return индексМладшей(рука, годные);
  }

  const некозырные = годные.filter(function (i) { return рука[i].масть !== партия.козырь; });
  if (некозырные.length > 0) return мелкаяСОглядкойНаПару(рука, некозырные);

  if (первыйХод) return индексМладшей(рука, годные);   // ходить всё равно надо
  // В руке одни козыри, а соперник берёт: отдавать их ему — расточительство,
  // лучше закончить подход.
  return -1;
}

/** Какую карту бот кладёт в атаку. Вернёт -1, если решил закончить подход. */
function выбратьКартуДляАтаки(партия, игрок, годные, первыйХод, сложность) {
  const рука = партия.руки[игрок];

  // Новичок время от времени кладёт что попало — бывает, что и козырь.
  if (сложность === 'лёгкий' && Math.random() < ДОЛЯ_ОШИБОК_ЛЁГКОГО) {
    return годные[Math.floor(Math.random() * годные.length)];
  }

  if (сложность === 'сложный') return выборСложного(партия, игрок, годные, первыйХод);

  const некозырные = годные.filter(function (i) { return рука[i].масть !== партия.козырь; });
  if (некозырные.length > 0) return индексМладшей(рука, некозырные);

  // В руке одни козыри: ходить всё равно надо, а берущему не жалко и козыря.
  if (первыйХод || партия.берёт) return индексМладшей(рука, годные);
  return -1;
}

/** Чем бот отбивается: список годных карт уже собран, надо выбрать одну. */
function выбратьКартуДляЗащиты(партия, игрок, годные, сложность) {
  const рука = партия.руки[игрок];

  // Новичок хватается за самую крупную карту, часто зря тратит козырь.
  if (сложность === 'лёгкий' && Math.random() < ДОЛЯ_ОШИБОК_ЛЁГКОГО) {
    return индексСтаршей(рука, годные);
  }

  // Бьём самой мелкой подходящей, козырь — только когда другого нет.
  const некозырные = годные.filter(function (i) { return рука[i].масть !== партия.козырь; });
  return индексМладшей(рука, некозырные.length > 0 ? некозырные : годные);
}

/** Один ход бота в роли атакующего (первая карта, подкидывание или «Бито»). */
function атакаБота(партия, игрок, сложность) {
  const рука = партия.руки[игрок];
  const первыйХод = партия.стол.length === 0;

  const годные = [];
  for (let i = 0; i < рука.length; i++) {
    if (можноПоложить(партия, рука[i])) годные.push(i);
  }
  // Нечего класть: заканчиваем подход. При пустом столе это возможно,
  // только когда партия и так уже фактически доиграна.
  if (годные.length === 0) {
    завершитьПодход(партия);
    return первыйХод ? 'пас' : 'бито';
  }

  const индекс = выбратьКартуДляАтаки(партия, игрок, годные, первыйХод, сложность);
  if (индекс === -1) {
    завершитьПодход(партия);
    return первыйХод ? 'пас' : 'бито';
  }

  положитьВАтаку(партия, игрок, индекс);
  return первыйХод ? 'ходит' : 'подкидывает';
}

/** Один ход бота в роли защищающегося: отбиться или взять. */
function защитаБота(партия, игрок, сложность) {
  const рука = партия.руки[игрок];
  let индексПары = -1;
  for (let i = 0; i < партия.стол.length; i++) {
    if (!партия.стол[i].защита) { индексПары = i; break; }
  }
  if (индексПары === -1) return 'нечего';

  const атака = партия.стол[индексПары].атака;
  const годные = [];
  for (let i = 0; i < рука.length; i++) {
    if (бьёт(рука[i], атака, партия.козырь)) годные.push(i);
  }
  if (годные.length === 0) {
    объявитьБеру(партия);
    return 'беру';
  }

  const индекс = выбратьКартуДляЗащиты(партия, игрок, годные, сложность);

  отбить(партия, индексПары, индекс);
  return 'отбивается';
}

/**
 * Сделать за игрока один ход по правилам бота.
 * Уровень можно передать третьим доводом — иначе берётся уровень партии.
 * Возвращает короткое название действия — оно нужно автотесту и отладке.
 */
function ходБота(партия, игрок, сложность) {
  if (партия.завершена) return 'конец';
  if (ктоХодит(партия) !== игрок) return 'не его ход';
  const уровень = проверитьСложность(сложность || партия.сложность);
  return фаза(партия) === 'защита'
    ? защитаБота(партия, игрок, уровень)
    : атакаБота(партия, игрок, уровень);
}

