/* Строка связи над столом одна, а пишут в неё двое: js/сеть.js рассказывает
   про друга и про обрыв, игра — про свой отправленный ход. Причём js/сеть.js
   освежает её раз в секунду, поэтому просто написать туда «Отправляем ход…»
   нельзя: надпись сотрут через секунду. Вести от сети держим отдельно и,
   пока ход летит, показываем поверх них своё ожидание. */
let вестиОСвязи = { текст: '', вид: '' };

/** Строка связи над столом: «ждём друга», «связь потеряна» и прочее. */
function показатьСвязь(текст, вид) {
  вестиОСвязи = { текст: текст || '', вид: вид || '' };
  нарисоватьСтрокуСвязи();
}

/** Собрать надпись: свой неотправленный ход важнее вестей о друге. */
function нарисоватьСтрокуСвязи() {
  const узел = эл('строка-связи');
  if (!узел) return;
  const текст = ждёмОтветСервера ? 'Отправляем ход…' : вестиОСвязи.текст;
  const вид = ждёмОтветСервера ? 'ожидание' : вестиОСвязи.вид;
  узел.textContent = текст;
  узел.classList.toggle('скрыт', !текст);
  узел.classList.toggle('связь--тревога', вид === 'тревога');
  узел.classList.toggle('связь--ожидание', вид === 'ожидание');
}

/** Переключить игру в сетевой режим и очистить всё, что осталось от прошлой партии. */
function начатьСетевуюПартию() {
  if (таймер !== null) {
    clearTimeout(таймер);
    таймер = null;
  }
  отменитьПоказИтога();
  убратьСобытие();
  выбраннаяКарта = null;
  итогЗасчитан = false;
  ждёмОтветПроВыход = false;
  ждёмОтветСервера = false;
  рукаГлухаДо = 0;
  номерПоказанногоСобытия = 0;
  сетьПредупредилаОРазладе = false;
  другУшёлИзПартии = false;
  насВывелиИзПартии = false;
  подсказкаПослеПартии = '';
  // Прошлая партия (хоть с ботом, хоть сетевая) забывается целиком:
  // иначе игра примет первое состояние от сервера за продолжение старой
  // и не покажет, кто ходит первым.
  партия = null;
  режим = РЕЖИМ_СЕТЬ;
  показатьЭкран('экран-игры');
  подобратьРазмерКарты();
}

/** Звук под чужой ход: охапка карт в руке шуршит иначе, чем одна карта по столу. */
function озвучитьСетевоеСобытие(былоВРуке) {
  if (партия.руки.человек.length > былоВРуке) звукВзятия();
  else звукКарты();
}

/** Новая раздача в той же комнате (реванш): стираем следы прошлой партии. */
function принятьНовуюРаздачу() {
  итогЗасчитан = false;
  ждёмОтветПроВыход = false;
  выбраннаяКарта = null;
  отменитьПоказИтога();       // итог прошлой партии поверх новой раздачи не нужен
  другУшёлИзПартии = false;   // раз играем дальше, друг за столом
  насВывелиИзПартии = false;  // и нас самих сервер снова считает за столом
  подсказкаПослеПартии = '';  // объяснение прошлой концовки к новой раздаче не относится
  показатьЭкран('экран-игры');
  написатьВРамкуИтога('');
}

/**
 * Главная дверь: сюда js/сеть.js отдаёт каждое новое состояние от сервера.
 * Всё, что игра показывает в сетевой партии, проходит через эту функцию.
 */
function показатьСетевоеСостояние(вид) {
  if (!вид) return;
  if (!этоСетеваяИгра()) начатьСетевуюПартию();

  const былоВРуке = партия ? партия.руки.человек.length : 0;
  const былаЗавершена = партия ? партия.завершена : false;
  const первыйПоказ = !партия;

  партия = партияИзВида(вид);
  сверитьОчередьХода(вид);

  // Партия была доиграна, а теперь идёт снова — значит, состоялся реванш.
  if (былаЗавершена && !партия.завершена) принятьНовуюРаздачу();

  const номер = целоеИзОтвета(вид.номерСобытия);
  if (первыйПоказ) {
    номерПоказанногоСобытия = номер;
    показатьСобытие(вид.яХожу ? 'Вы ходите первым' : 'Первым ходит друг', ПОКАЗ_НАЧАЛА);
  } else if (номер !== номерПоказанногоСобытия) {
    номерПоказанногоСобытия = номер;
    if (вид.событие) показатьСобытие(вид.событие);
    озвучитьСетевоеСобытие(былоВРуке);
  }

  перерисовать();

  if (партия.завершена) подвестиСетевойИтог(вид);
}

/**
 * Итог сетевой партии. В таблицу рекордов он не идёт: там серия побед
 * над ботом определённого уровня, и мешать с ней победы над живым другом
 * нельзя — рекорды перестанут что-либо значить.
 */
function подвестиСетевойИтог(вид) {
  /* Друг мог уйти двумя способами: бросить партию посреди игры или отказаться
     от реванша после честного конца. В обоих случаях звать больше некого,
     поэтому кнопку прячем сразу — плашка итога могла появиться и раньше. */
  другУшёлИзПартии = Boolean(вид.соперникУшёл) || партия.результат === 'друг-ушёл';
  /* А здесь обратный случай: из партии вывели нас самих. Реванш в такой
     комнате сервер уже не даст, поэтому кнопку тоже прячем. */
  насВывелиИзПартии = партия.результат === 'связь-потеряна';
  показатьЭлемент('кнопка-ещё', реваншВозможен());

  if (!итогЗасчитан) {
    итогЗасчитан = true;
    if (партия.результат === 'бот') звукПобеды();
    else if (партия.результат === 'человек') звукПроигрыша();
    // Плашку показываем с задержкой: сначала пусть игрок увидит последний ход.
    отменитьПоказИтога();
    таймерИтога = setTimeout(показатьРезультат, 1200);
  }
  показатьКонцовку(разобратьКонцовку(вид));
}

/**
 * Что показать после партии вдвоём — двумя частями, потому что на экране
 * итога два разных места для текста.
 *
 * «рамка» — та самая рамка под заголовком, где в игре с ботом стоит
 * «Побед подряд: 3». Она крупная и жирная и рассчитана на короткий статус
 * в пару слов, поэтому длинным объяснениям там не место.
 *
 * «подсказка» — вторая фраза обычной подписью под заголовком: там спокойно
 * помещается объяснение, что случилось и что делать дальше.
 */
function разобратьКонцовку(вид) {
  // Нас вывели из партии — звать на реванш нечем и незачем, даже если друг
  // успел позвать нас первым: сервер этой комнаты нас уже не пустит.
  // Что делать дальше, сказано прямо в подписи итога, второй раз не повторяем.
  if (партия && партия.результат === 'связь-потеряна') {
    return { рамка: '', подсказка: '' };
  }
  if (вид.соперникУшёл) {
    // Партия оборвалась на середине: про уход крупно написано в заголовке,
    // поэтому здесь только про то, что делать дальше.
    if (партия && партия.результат === 'друг-ушёл') {
      return {
        рамка: '',
        подсказка: 'Позвать на реванш уже некого — вернитесь в меню и начните новую игру.'
      };
    }
    // А здесь партия доиграна честно, в заголовке стоит «Вы выиграли!»
    // или «Вы проиграли», и про ушедшего друга человек ещё не знает.
    return {
      рамка: '',
      подсказка: 'Друг уже вышел из игры, реванша не будет — вернитесь в меню и начните новую.'
    };
  }
  if (вид.яХочуЕщё) return мыПозвалиНаРеванш();
  if (вид.соперникХочетЕщё) {
    return { рамка: 'Друг зовёт сыграть ещё — жмите «Ещё партию»', подсказка: '' };
  }
  return { рамка: 'В таблицу рекордов партии с другом не идут', подсказка: '' };
}

/**
 * Мы позвали друга на реванш и ждём ответа. В рамке — короткое ожидание,
 * само предложение уходит в подпись: вместе они не влезали в рамку и
 * растягивали её на две строки.
 */
function мыПозвалиНаРеванш() {
  return { рамка: 'Ждём друга…', подсказка: 'Вы предложили сыграть ещё.' };
}

/** Разложить концовку по местам: короткое — в рамку, объяснение — в подпись. */
function показатьКонцовку(концовка) {
  подсказкаПослеПартии = концовка.подсказка || '';
  написатьВРамкуИтога(концовка.рамка || '');
  обновитьТекстыИтога();
}

