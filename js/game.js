/* ---------------------------------------------------------------------
   Звук. Файлов со звуками в проекте нет: короткие сигналы собираются
   прямо в браузере через Web Audio API.
   --------------------------------------------------------------------- */

const ГРОМКОСТЬ = 0.07;   // тихо: игра часто идёт в наушниках в транспорте
let звуковойДвижок = null;

/** Звуковой движок браузера. Создаём при первом звуке: до нажатия кнопки браузер его не даёт. */
function получитьЗвуковойДвижок() {
  if (звуковойДвижок) return звуковойДвижок;
  try {
    const Движок = window.AudioContext || window.webkitAudioContext;
    if (!Движок) return null;
    звуковойДвижок = new Движок();
  } catch (ошибка) {
    звуковойДвижок = null;
  }
  return звуковойДвижок;
}

/**
 * Один короткий сигнал: частота в герцах, длительность и задержка в секундах.
 * Нарастание и затухание нужны обязательно — без них слышен щелчок на краях.
 */
function сигнал(частота, длительность, задержка) {
  if (!звукВключён) return;
  const движок = получитьЗвуковойДвижок();
  if (!движок) return;
  try {
    if (движок.state === 'suspended') движок.resume();
    const начало = движок.currentTime + (задержка || 0);
    const генератор = движок.createOscillator();
    const громкость = движок.createGain();
    генератор.type = 'triangle';        // мягче синуса и без резкости квадрата
    генератор.frequency.setValueAtTime(частота, начало);
    громкость.gain.setValueAtTime(0.0001, начало);
    громкость.gain.exponentialRampToValueAtTime(ГРОМКОСТЬ, начало + 0.012);
    громкость.gain.exponentialRampToValueAtTime(0.0001, начало + длительность);
    генератор.connect(громкость);
    громкость.connect(движок.destination);
    генератор.start(начало);
    генератор.stop(начало + длительность + 0.02);
  } catch (ошибка) {
    /* звук — не то, ради чего стоит ронять игру */
  }
}

function звукКарты()     { сигнал(330, 0.07); }
function звукВзятия()    { сигнал(190, 0.14); }
function звукПобеды()    { сигнал(523, 0.12); сигнал(784, 0.20, 0.13); }
function звукПроигрыша() { сигнал(300, 0.16); сигнал(160, 0.30, 0.16); }

