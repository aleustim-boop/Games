/* =====================================================================
   Подкидной дурак — правила партии и отрисовка стола.

   Файл намеренно разделён на две части:
     ЧАСТЬ 1 «Правила» — работают только с объектом состояния «партия»,
             про экран и про кнопки ничего не знают. Их можно прогнать
             без браузера (автотест «бот против бота»);
     ЧАСТЬ 2 «Экран»  — по состоянию партии рисует картинку целиком,
             своих правил не придумывает.

   Разделение нужно, чтобы ошибку было видно сразу: если карта ушла
   не туда — это часть 1, если карта не там нарисовалась — часть 2.
   ===================================================================== */

'use strict';

/* =====================================================================
   ЧАСТЬ 1. ПРАВИЛА ПАРТИИ
   ===================================================================== */

const МАСТИ = ['♠', '♥', '♦', '♣']; // пики, черви, бубны, трефы
const КРАСНЫЕ_МАСТИ = ['♥', '♦'];

/* Колод у игры две. На двоих-четверых играют привычной колодой в 36 карт
   (от шестёрки до туза). На пятерых-шестерых её не хватает: шестеро по шесть
   карт — это ровно 36, вся колода уходит в раздачу, козырной карте взяться
   неоткуда и добирать нечем. Поэтому с пяти игроков берём колоду в 52 карты —
   те же масти, только младших карт больше (двойки, тройки, четвёрки, пятёрки).

   Достоинства перечислены по возрастанию, а вес карты — её место в списке
   плюс два. Так шестёрка весит 6 в любой колоде, и старшинство карт
   от размера колоды не зависит вовсе. */
const ВСЕ_ДОСТОИНСТВА = ['2', '3', '4', '5', '6', '7', '8', '9', '10', 'В', 'Д', 'К', 'Т'];
const КОЛОДА_36 = 36;
const КОЛОДА_52 = 52;
const МЛАДШЕЕ_В_КОЛОДЕ_36 = '6';

/** Достоинства выбранной колоды: у большой — все, у обычной — от шестёрки. */
function достоинстваКолоды(размерКолоды) {
  if (размерКолоды === КОЛОДА_52) return ВСЕ_ДОСТОИНСТВА.slice();
  return ВСЕ_ДОСТОИНСТВА.slice(ВСЕ_ДОСТОИНСТВА.indexOf(МЛАДШЕЕ_В_КОЛОДЕ_36));
}

// Достоинства обычной колоды. Отдаются наружу ради проверок и старого кода,
// который про большую колоду ещё не знает.
const ДОСТОИНСТВА = достоинстваКолоды(КОЛОДА_36);

const КАРТ_В_РУКЕ = 6;          // до скольки карт добирают из колоды
const МАКС_КАРТ_В_ПОДХОДЕ = 6;  // больше шести карт за один подход не кладут

/* Сколько человек может сесть за стол. Двое — это не отдельная игра,
   а самый маленький круг: правила ниже написаны для круга любого размера,
   и на двоих они сами собой сворачиваются в привычную игру «один ходит,
   второй отбивается». */
const МИН_ИГРОКОВ = 2;
const МАКС_ИГРОКОВ = 6;
const ПОРОГ_БОЛЬШОЙ_КОЛОДЫ = 5;   // с пяти игроков играем колодой в 52 карты

/* Две необязательные разновидности игры. Обе по умолчанию выключены: без них
   партия идёт ровно так же, как шла всегда, — это нарочно, чтобы привычная
   игра с ботом и по сети не изменилась ни на йоту.

   «Переводной» ({ переводной: true }) — отбивающийся вместо того, чтобы крыть,
   кладёт карту того же достоинства, что уже лежит на столе, и отбиваться
   приходится следующему по кругу. Подробности — у функции «можноПеревести».

   «Парами» ({ парами: true }) — игра двое на двоих, партнёры сидят через
   одного. Подробности — у функции «партнёр». */
const ИГРОКОВ_В_ПАРАХ = 4;        // игра парами бывает только вчетвером

/* Имена мест за столом. Первые два нарочно оставлены прежними: на слова
   «человек» и «бот» завязаны игра с ботом, сервер игры вдвоём и все
   накопленные проверки. Кто садится на место — живой человек или робот —
   правилам всё равно, это решает тот, кто создаёт партию. */
const ИМЕНА_МЕСТ = ['человек', 'бот', 'бот-3', 'бот-4', 'бот-5', 'бот-6'];

// Уровни соперника. Эти же слова показываются в меню и попадают в таблицу рекордов.
const СЛОЖНОСТИ = ['лёгкий', 'обычный', 'сложный'];
const СЛОЖНОСТЬ_ПО_УМОЛЧАНИЮ = 'обычный';

/** Незнакомое слово превращаем в «обычный», чтобы игра не зависела от опечатки. */
function проверитьСложность(значение) {
  return СЛОЖНОСТИ.indexOf(значение) !== -1 ? значение : СЛОЖНОСТЬ_ПО_УМОЛЧАНИЮ;
}

/**
 * Собрать полную колоду нужного размера (36 или 52 карты; без указания — 36).
 * Вес — число от 2 до 14, по нему сравниваем карты: так не нужно каждый раз
 * искать достоинство в списке.
 */
function собратьКолоду(размерКолоды) {
  const достоинства = достоинстваКолоды(размерКолоды || КОЛОДА_36);
  const колода = [];
  for (const масть of МАСТИ) {
    for (const имя of достоинства) {
      колода.push({ масть: масть, имя: имя, вес: ВСЕ_ДОСТОИНСТВА.indexOf(имя) + 2 });
    }
  }
  return колода;
}

/** Перетасовать колоду (алгоритм Фишера — Йетса, честное перемешивание). */
function перемешать(колода) {
  for (let i = колода.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const временно = колода[i];
    колода[i] = колода[j];
    колода[j] = временно;
  }
  return колода;
}

/**
 * Карты в руке держим по порядку: сначала некозырные по мастям,
 * козыри — в конце. Нужно только для удобства человека, на правила не влияет.
 */
function упорядочитьРуку(партия, игрок) {
  if (!партия.руки[игрок]) return;   // за таким именем никто не сидит — раскладывать нечего
  партия.руки[игрок].sort(function (а, б) {
    const аКозырь = а.масть === партия.козырь;
    const бКозырь = б.масть === партия.козырь;
    if (аКозырь !== бКозырь) return аКозырь ? 1 : -1;
    if (а.масть !== б.масть) return МАСТИ.indexOf(а.масть) - МАСТИ.indexOf(б.масть);
    return а.вес - б.вес;
  });
}

/** Целое число из настроек; мусор превращается в null, а не в ноль. */
function целоеИлиНичего(значение) {
  const число = Number(значение);
  return Number.isFinite(число) ? Math.floor(число) : null;
}

/**
 * Имена мест за столом. Можно задать числом («посади четверых») или списком
 * своих имён — второе понадобится игре по сети, где места зовут по игрокам.
 *
 * Второй довод — «просят играть парами». Тогда стол по умолчанию на четверых
 * и длиннее четырёх не бывает: игра парами других размеров не знает.
 */
function местаЗаСтолом(настройки, просятПарами) {
  const потолок = просятПарами ? ИГРОКОВ_В_ПАРАХ : МАКС_ИГРОКОВ;
  if (Array.isArray(настройки.игроки)) {
    const свои = настройки.игроки
      .filter(function (имя) { return typeof имя === 'string' && имя.trim() !== ''; })
      .map(function (имя) { return имя.trim(); })
      .filter(function (имя, i, все) { return все.indexOf(имя) === i; });  // повторов быть не должно
    if (свои.length >= МИН_ИГРОКОВ) return свои.slice(0, потолок);
  }
  const сколько = целоеИлиНичего(настройки.игроков) || (просятПарами ? ИГРОКОВ_В_ПАРАХ : МИН_ИГРОКОВ);
  const сколькоВПределах = Math.min(потолок, Math.max(МИН_ИГРОКОВ, сколько));
  return ИМЕНА_МЕСТ.slice(0, сколькоВПределах);
}

/**
 * Какой колодой играем. По умолчанию решает число игроков: до четверых —
 * привычные 36 карт, с пяти — 52. Просьбу взять другую колоду выполняем,
 * только если карт хватит на раздачу и ещё останется козырная под колодой.
 */
function выбратьРазмерКолоды(сколькоИгроков, желаемый) {
  const поЧислуИгроков = сколькоИгроков >= ПОРОГ_БОЛЬШОЙ_КОЛОДЫ ? КОЛОДА_52 : КОЛОДА_36;
  if (желаемый !== КОЛОДА_36 && желаемый !== КОЛОДА_52) return поЧислуИгроков;
  return желаемый > сколькоИгроков * КАРТ_В_РУКЕ ? желаемый : поЧислуИгроков;
}

/**
 * Разобрать настройки партии. Раньше сюда передавали одну строку — уровень
 * соперника, и так до сих пор делают игра с ботом, сервер и все проверки.
 * Поэтому строка (и вообще что угодно, кроме объекта) означает ровно то же,
 * что и раньше: двое игроков, колода 36, названный уровень.
 */
function разобратьНастройки(настройки) {
  const этоНабор = Boolean(настройки) && typeof настройки === 'object' && !Array.isArray(настройки);
  const набор = этоНабор ? настройки : {};
  const просятПарами = набор.парами === true;
  const игроки = местаЗаСтолом(набор, просятПарами);
  return {
    сложность: проверитьСложность(этоНабор ? набор.сложность : настройки),
    игроки: игроки,
    размерКолоды: выбратьРазмерКолоды(игроки.length, целоеИлиНичего(набор.колода)),
    // Разновидности включаются только словом «да» и только из набора настроек:
    // строка-уровень («сложный») никогда не должна случайно включить режим.
    переводной: набор.переводной === true,
    // Парами играют строго вчетвером. Если за столом собралось другое число
    // игроков, просьбу выполнить нечем — играем обычную партию, а не наполовину
    // парную: половинчатые правила хуже, чем понятные привычные.
    парами: просятПарами && игроки.length === ИГРОКОВ_В_ПАРАХ
  };
}

/**
 * Новая партия: тасуем колоду, раздаём по 6 карт, козырь — последняя карта
 * колоды (она лежит под колодой и достаётся последней).
 *
 * Довод — либо уровень соперника строкой (как было всегда), либо набор
 * настроек: { сложность, игроков: 2…6, игроки: [имена], колода: 36 или 52,
 * переводной: true, парами: true }. Обе разновидности по умолчанию выключены.
 */
function создатьПартию(настройки) {
  const выбор = разобратьНастройки(настройки);
  const колода = перемешать(собратьКолоду(выбор.размерКолоды));
  const козырнаяКарта = колода[колода.length - 1];

  const партия = {
    сложность: выбор.сложность,     // каким соперником играет бот
    игроки: выбор.игроки,           // места за столом по кругу, по часовой стрелке
    переводной: выбор.переводной,   // разрешено ли переводить ход картой того же достоинства
    парами: выбор.парами,           // играем ли двое на двоих
    проигравшие: [],                // кто остался дураком: один игрок, а в игре парами — оба из пары
    выбывшие: [],                   // кто остался без карт при пустой колоде и вышел из партии
    размерКолоды: выбор.размерКолоды,
    колода: колода,                 // колода[0] — верхняя карта, последняя — козырная
    козырь: козырнаяКарта.масть,
    козырнаяКарта: козырнаяКарта,
    руки: {},                       // на каждое место — свой список карт
    стол: [],                       // список пар { атака: карта, защита: карта или null }
    отбой: [],                      // сюда уходят отбитые карты
    атакует: выбор.игроки[0],
    /* Кто в этом подходе уже сказал «больше не подкидываю». Отказ держится
       до конца подхода, и забываем его только там, где положение вправду
       изменилось: защитник отбился картой нового достоинства, сказал «Беру»
       или ход перевели на другого. От чужой подкинутой карты у спасовавшего
       ничего нового не появляется — значит, и спрашивать его не за что. */
    пасы: [],
    берёт: false,                   // защищающийся сказал «Беру»
    завершена: false,
    // Имя дурака, либо 'ничья'. В игре парами — оба имени через « и »:
    // читать итог по одному имени там нечего, дурак не человек, а пара.
    результат: null
  };

  // Раздаём по одной карте по кругу, как в жизни.
  for (const имя of партия.игроки) партия.руки[имя] = [];
  for (let i = 0; i < КАРТ_В_РУКЕ; i++) {
    for (const имя of партия.игроки) партия.руки[имя].push(партия.колода.shift());
  }
  партия.атакует = ктоХодитПервым(партия);
  упорядочитьРуку(партия, партия.игроки[0]);
  return партия;
}

/** Самый младший козырь в руке (или null, если козырей нет). */
function младшийКозырь(партия, игрок) {
  let младший = null;
  for (const карта of партия.руки[игрок]) {
    if (карта.масть !== партия.козырь) continue;
    if (младший === null || карта.вес < младший.вес) младший = карта;
  }
  return младший;
}

/**
 * Первым ходит тот, у кого младший козырь за всем столом.
 * Козырей нет ни у кого — ходит тот, кто сидит первым.
 */
function ктоХодитПервым(партия) {
  let первый = партия.игроки[0];
  let младший = null;
  for (const имя of партия.игроки) {
    const козырь = младшийКозырь(партия, имя);
    if (!козырь) continue;
    if (младший === null || козырь.вес < младший.вес) {
      младший = козырь;
      первый = имя;
    }
  }
  return первый;
}

/* ---------------------------------------------------------------------
   Круг игроков. Здесь собрано всё, что отвечает на два вопроса:
   «кто отбивается» и «кому переходит ход». Ради этого они и живут
   в одном месте: в переводном дураке и в игре парами меняются
   именно эти два ответа, а остальные правила остаются прежними.
   --------------------------------------------------------------------- */

/** Играет ли этот игрок ещё — или уже вышел, оставшись без карт. */
function вИгре(партия, игрок) {
  return !партия.выбывшие || партия.выбывшие.indexOf(игрок) === -1;
}

/** Все, кто ещё в партии, в порядке мест за столом. */
function оставшиеся(партия) {
  return партия.игроки.filter(function (имя) { return вИгре(партия, имя); });
}

/** Обойти круг начиная с этого места; выбывших пропускаем — их за столом уже нет. */
function поКругуОт(партия, откого) {
  const места = партия.игроки;
  const начало = места.indexOf(откого);
  const круг = [];
  for (let шаг = 0; шаг < места.length; шаг++) {
    const имя = места[((начало === -1 ? 0 : начало) + шаг) % места.length];
    if (вИгре(партия, имя)) круг.push(имя);
  }
  return круг;
}

/** Следующий по кругу за этим местом. Вдвоём это просто второй игрок. */
function следующийВКруге(партия, откого) {
  const круг = поКругуОт(партия, откого);
  if (круг.length === 0) return откого;          // все вышли, партия и так окончена
  return круг[0] === откого ? (круг[1] || откого) : круг[0];
}

/**
 * Партнёр этого игрока в игре парами — тот, кто сидит через одного, напротив:
 * первый с третьим, второй с четвёртым. Вне игры парами партнёров нет
 * ни у кого, поэтому ответ — null.
 *
 * Партнёрство считается по местам за столом, а не по остатку игроков:
 * даже если напарник уже вышел без карт, он остаётся напарником, и подкидывать
 * ему по-прежнему нельзя — просто подкидывать уже нечего.
 */
function партнёр(партия, игрок) {
  if (!партия.парами) return null;
  const место = партия.игроки.indexOf(игрок);
  if (место === -1) return null;
  return партия.игроки[(место + 2) % партия.игроки.length];
}

/**
 * Это он сам или его напарник? Короткий вопрос, который правила ниже задают
 * трижды: кому не ходят, кому не подкидывают и кто с кем проигрывает.
 * Вне игры парами напарников нет, поэтому ответ «да» — только про самого себя,
 * и все правила сворачиваются в прежние.
 */
function самИлиНапарник(партия, кто, другой) {
  return кто === другой || партнёр(партия, кто) === другой;
}

/**
 * Кто отбивался бы, если бы ходил названный игрок. Вопрос вынесен отдельно,
 * потому что его задают дважды: про нынешнего атакующего — постоянно,
 * а перевод спрашивает заранее: «кому достанется защита, если я переведу?».
 *
 * В игре парами ответ отличается одним: своему партнёру не ходят. Если сосед
 * по кругу — напарник (такое бывает, когда соперник между ними уже вышел
 * без карт), его пропускаем и отбиваться зовём следующего соперника.
 */
function ктоОтбиваетсяЗа(партия, атакующий) {
  if (!партия.парами) return следующийВКруге(партия, атакующий);
  for (const имя of поКругуОт(партия, атакующий)) {
    if (!самИлиНапарник(партия, атакующий, имя)) return имя;
  }
  return атакующий;   // за столом остались одни напарники — партия уже кончена
}

/** Кто сейчас отбивается — следующий по кругу за тем, кто ходит. */
function защищается(партия) {
  return ктоОтбиваетсяЗа(партия, партия.атакует);
}

/**
 * Кому разрешено подкидывать и в каком порядке: сначала тот, кто ходил,
 * дальше по кругу. Отбивающийся себе не подкидывает, поэтому его в списке нет.
 * Вдвоём в списке остаётся один игрок — тот, кто ходит.
 *
 * В игре парами из списка выпадает ещё и напарник отбивающегося: подкидывают
 * только соперники. Иначе пара топила бы сама себя — карты партнёра для неё
 * такие же свои, как собственные.
 */
function подкидывающие(партия) {
  const защитник = защищается(партия);
  return поКругуОт(партия, партия.атакует).filter(function (имя) {
    return !самИлиНапарник(партия, защитник, имя);
  });
}

/** Может ли этот игрок положить карту в атаку прямо сейчас. */
function можетПодкидывать(партия, игрок) {
  // Вышедшему из игры и после конца партии класть карты нельзя никому.
  if (партия.завершена || !вИгре(партия, игрок)) return false;
  // Первую карту подхода кладёт только тот, чей ход: подкидывать ещё не к чему.
  if (партия.стол.length === 0) return игрок === партия.атакует;
  // Нельзя класть карту ни отбивающемуся, ни (в игре парами) его напарнику.
  return !самИлиНапарник(партия, защищается(партия), игрок);
}

/**
 * Что сейчас происходит за столом. Фазу не храним, а вычисляем по столу —
 * тогда её невозможно «забыть переключить» и получить зависание.
 *   'атака'       — стол пуст, атакующий должен положить карту;
 *   'защита'      — на столе есть неотбитая карта, ход защищающегося;
 *   'подкидывание'— всё отбито, атакующий может подкинуть или сказать «Бито»;
 *   'докидывание' — защищающийся берёт, атакующий может докинуть карты;
 *   'конец'       — партия окончена.
 */
function фаза(партия) {
  if (партия.завершена) return 'конец';
  if (партия.стол.length === 0) return 'атака';
  if (партия.берёт) return 'докидывание';
  for (const пара of партия.стол) {
    if (!пара.защита) return 'защита';
  }
  return 'подкидывание';
}

/**
 * Найдётся ли у игрока карта, которую прямо сейчас разрешено подкинуть.
 * Считаем честно, по столу: подкидывают только тем достоинством, которое
 * на столе уже лежит, и только пока стол не упёрся в потолок.
 */
function найдётсяЧемПодкинуть(партия, игрок) {
  const рука = партия.руки[игрок] || [];
  for (const карта of рука) {
    if (можноПоложить(партия, карта)) return true;
  }
  return false;
}

/**
 * Ждём ли мы слова от этого игрока. Не ждём двоих: того, кто уже сказал
 * «больше не подкидываю», и того, кому подкинуть просто нечем — его ответ
 * известен заранее по картам, и спрашивать его значит зря дёргать человека
 * кнопкой, которую можно нажать только одним способом.
 *
 * Этой же меркой пользуется «пас», и это важно: разойдись они хоть на шаг —
 * один ждал бы слова от того, кого другой уже пропустил, и подход завис бы.
 */
function ждётСлова(партия, игрок) {
  const пасы = партия.пасы || [];
  if (пасы.indexOf(игрок) !== -1) return false;
  return найдётсяЧемПодкинуть(партия, игрок);
}

/**
 * Чьё сейчас слово: имя игрока или null, если партия окончена.
 * В подкидывании и докидывании право высказаться обходит по кругу всех,
 * кому разрешено подкинуть: сказавших «больше не подкидываю» и тех, кому
 * подкинуть нечем, пропускаем.
 * Вдвоём подкидывающий один, поэтому очередь всегда возвращается к нему —
 * ровно как было до появления круга.
 */
function ктоХодит(партия) {
  const текущая = фаза(партия);
  if (текущая === 'конец') return null;
  if (текущая === 'защита') return защищается(партия);
  if (текущая === 'атака') return партия.атакует;
  for (const имя of подкидывающие(партия)) {
    if (ждётСлова(партия, имя)) return имя;
  }
  return партия.атакует;   // сказать больше некому — подход закончит тот, кто ходил
}

/** Бьёт ли карта «чем» карту «что»: старше той же масти либо козырь по некозырю. */
function бьёт(чем, что, козырь) {
  if (чем.масть === что.масть) return чем.вес > что.вес;
  return чем.масть === козырь && что.масть !== козырь;
}

/** Сколько карт на столе ещё не отбито. */
function неотбитых(партия) {
  let счёт = 0;
  for (const пара of партия.стол) if (!пара.защита) счёт++;
  return счёт;
}

/** Достоинства всех карт на столе — только ими разрешено подкидывать. */
function достоинстваНаСтоле(партия) {
  const список = [];
  for (const пара of партия.стол) {
    if (список.indexOf(пара.атака.имя) === -1) список.push(пара.атака.имя);
    if (пара.защита && список.indexOf(пара.защита.имя) === -1) список.push(пара.защита.имя);
  }
  return список;
}

/**
 * Можно ли сейчас положить эту карту в атаку.
 * Два ограничения: не больше шести карт за подход и не больше,
 * чем карт в руке у того, кто отбивается (иначе ему нечем крыть).
 */
function можноПоложить(партия, карта) {
  const текущая = фаза(партия);
  if (текущая !== 'атака' && текущая !== 'подкидывание' && текущая !== 'докидывание') return false;
  if (партия.стол.length >= МАКС_КАРТ_В_ПОДХОДЕ) return false;
  if (неотбитых(партия) >= партия.руки[защищается(партия)].length) return false;
  if (текущая === 'атака') return true;
  return достоинстваНаСтоле(партия).indexOf(карта.имя) !== -1;
}

/** Положить карту из руки в атаку. Возвращает true, если ход состоялся. */
function положитьВАтаку(партия, игрок, индексКарты) {
  if (!можетПодкидывать(партия, игрок)) return false;
  const рука = партия.руки[игрок];
  const карта = рука ? рука[индексКарты] : null;
  if (!карта || !можноПоложить(партия, карта)) return false;
  рука.splice(индексКарты, 1);
  партия.стол.push({ атака: карта, защита: null });
  /* Отказы здесь нарочно не сбрасываются. Подкинуть можно только тем
     достоинством, которое на столе уже лежало, — значит, у сказавшего
     «больше не подкидываю» от чужой карты ничего нового не появилось,
     и спрашивать его заново не за что. Раньше список отказов чистился
     после каждой карты, и слово всё время возвращалось к атакующему:
     живой игрок жаловался, что его дёргают на каждый чужой ход. */
  return true;
}

/**
 * Отбить карту на столе. Возвращает true, если получилось.
 *
 * Здесь же — единственный случай, когда на столе появляется достоинство,
 * которого не было: подкидывают-то только тем, что уже лежит, а отбиваются
 * чем придётся. Появилось новое достоинство — у всех вправду появилось,
 * чем подкинуть, и прежние отказы больше ничего не значат: спрашиваем круг
 * заново.
 */
function отбить(партия, индексПары, индексКарты) {
  if (фаза(партия) !== 'защита') return false;
  const пара = партия.стол[индексПары];
  if (!пара || пара.защита) return false;
  const защитник = защищается(партия);
  const карта = партия.руки[защитник][индексКарты];
  if (!карта || !бьёт(карта, пара.атака, партия.козырь)) return false;
  const достоинствоНовое = достоинстваНаСтоле(партия).indexOf(карта.имя) === -1;
  пара.защита = карта;
  партия.руки[защитник].splice(индексКарты, 1);
  if (достоинствоНовое) партия.пасы = [];
  return true;
}

/**
 * Можно ли сейчас перевести ход этой картой (только в переводном дураке).
 *
 * Перевод — это когда отбивающийся не кроет карту, а кладёт рядом свою
 * такого же достоинства: «не я отбиваюсь, а следующий за мной». Стол
 * при этом растёт, и разбираться с ним придётся уже соседу.
 *
 * Условий четыре, и каждое взято из живой игры:
 *   1. карта того же достоинства, что уже лежит на столе, — иначе это
 *      не перевод, а просто чужая карта;
 *   2. ни одна карта подхода ещё не отбита. Как только защитник хоть раз
 *      покрыл, он признал подход своим — переводить поздно;
 *   3. у того, кому переводят, карт в руке хватает на весь стол: иначе
 *      его загоняют в положение, где отбиться невозможно физически.
 *      Это то же правило, что и при подкидывании, только считаем наперёд;
 *   4. потолок в шесть карт за подход действует и здесь.
 * Переводить самому себе нельзя — за столом должен быть кто-то ещё.
 */
function можноПеревести(партия, карта) {
  if (!партия.переводной || !карта) return false;
  if (фаза(партия) !== 'защита') return false;
  if (неотбитых(партия) !== партия.стол.length) return false;      // условие 2
  if (партия.стол.length >= МАКС_КАРТ_В_ПОДХОДЕ) return false;     // условие 4
  if (достоинстваНаСтоле(партия).indexOf(карта.имя) === -1) return false;   // условие 1
  const защитник = защищается(партия);
  // Перевод сдвигает круг: отбиваться будет тот, кто отбивался бы за переводящим.
  const следующий = ктоОтбиваетсяЗа(партия, защитник);
  if (следующий === защитник) return false;                        // за столом больше никого
  return партия.руки[следующий].length >= партия.стол.length + 1;  // условие 3
}

/**
 * Перевести ход картой из руки защищающегося. Возвращает true, если получилось.
 *
 * Вся хитрость перевода умещается в одну строку: переведший становится
 * атакующим. Дальше круг сам разбирается, кто отбивается и кто подкидывает, —
 * поэтому остальные правила игры про перевод знать не обязаны.
 */
function перевести(партия, индексКарты) {
  if (партия.завершена || !партия.переводной) return false;
  if (фаза(партия) !== 'защита') return false;
  const защитник = защищается(партия);
  const рука = партия.руки[защитник];
  const карта = рука ? рука[индексКарты] : null;
  if (!карта || !можноПеревести(партия, карта)) return false;
  рука.splice(индексКарты, 1);
  партия.стол.push({ атака: карта, защита: null });
  /* Круг сдвинулся: отбиваться теперь будет другой человек, и подкидывают
     тоже уже другие — в их числе прежний отбивавшийся, которого до сих пор
     никто не спрашивал. Прежние отказы были про другое положение, поэтому
     здесь их забываем и спрашиваем круг заново. */
  партия.пасы = [];
  партия.атакует = защитник;
  return true;
}

/**
 * «Беру»: защищающийся отказался отбиваться, дальше атакующий может докинуть.
 *
 * Отказы забываем: подкинуть тому, кто берёт, — совсем не то же самое, что
 * подкинуть тому, кто отбивается. Кто раньше сказал «больше не подкидываю»,
 * теперь вправе передумать, и спросить его честно — за подход такое случается
 * один раз, а не на каждую карту.
 */
function объявитьБеру(партия) {
  if (фаза(партия) !== 'защита') return false;
  партия.берёт = true;
  партия.пасы = [];
  return true;
}

/**
 * «Больше не подкидываю». Пока в круге есть кто-то, от кого мы ещё ждём
 * слова, подход продолжается и слово переходит к нему. Ждать больше некого —
 * подход закончен.
 *
 * Отказ держится до конца подхода: сказавшего «не подкидываю» больше
 * не спрашивают, пока положение вправду не изменится (см. «пасы» ниже).
 *
 * Вдвоём подкидывающий один, поэтому его отказ сразу заканчивает подход:
 * это и есть привычное «Бито».
 */
function пас(партия, игрок) {
  if (партия.завершена) return false;
  const текущая = фаза(партия);
  if (текущая !== 'атака' && текущая !== 'подкидывание' && текущая !== 'докидывание') return false;
  // Отказаться может только тот, кому вообще разрешено класть карту:
  // при пустом столе это один ходящий, дальше — все, кроме отбивающегося.
  if (!можетПодкидывать(партия, игрок)) return false;
  // Стол пуст: подкидывать не к чему, значит подход заканчивается сразу.
  if (текущая === 'атака') return завершитьПодход(партия);

  if (!партия.пасы) партия.пасы = [];
  if (партия.пасы.indexOf(игрок) === -1) партия.пасы.push(игрок);
  for (const имя of подкидывающие(партия)) {
    if (ждётСлова(партия, имя)) return true;   // от кого-то ещё ждём слова
  }
  return завершитьПодход(партия);
}

/**
 * Порядок добора после подхода: первым добирает тот, кто ходил, дальше
 * по кругу, отбивавшийся — последним. Вдвоём это привычные «сначала
 * атакующий, потом защищающийся».
 *
 * Считаем по кругу, а не по списку подкидывающих: добирают все, кто за столом.
 * В игре парами напарник отбивающегося карт не подкидывает, но добирает
 * наравне со всеми — иначе он остался бы без карт ни за что.
 */
function порядокДобора(партия) {
  const защитник = защищается(партия);
  const остальные = поКругуОт(партия, партия.атакует).filter(function (имя) {
    return имя !== защитник;
  });
  return остальные.concat([защитник]);
}

/** Добор из колоды до шести карт. */
function добрать(партия) {
  for (const игрок of порядокДобора(партия)) {
    while (партия.руки[игрок].length < КАРТ_В_РУКЕ && партия.колода.length > 0) {
      партия.руки[игрок].push(партия.колода.shift());
    }
  }
}

/**
 * Кто остался без карт при пустой колоде — тот вышел из игры, и партия
 * продолжается без него. Смотрим только после добора: пока в колоде есть
 * карты, пустая рука — не выход, а повод добрать.
 */
function отметитьВыбывших(партия) {
  if (партия.колода.length > 0) return;
  for (const имя of оставшиеся(партия)) {
    if (партия.руки[имя].length === 0) партия.выбывшие.push(имя);
  }
}

/**
 * Обе пары стола — по двое сидящих через одного. Нужны только игре парами.
 */
function пары(партия) {
  return [
    [партия.игроки[0], партия.игроки[2]],
    [партия.игроки[1], партия.игроки[3]]
  ];
}

/**
 * Записать конец партии: кто остался дураком. Одному имени — имя, двоим —
 * «имя и имя», никому — ничья. Список имён кладём отдельно, чтобы экрану
 * и серверу не пришлось разбирать строку обратно.
 */
function записатьИтог(партия, проигравшие) {
  партия.завершена = true;
  партия.проигравшие = проигравшие;
  партия.результат = проигравшие.length === 0 ? 'ничья' : проигравшие.join(' и ');
}

/**
 * Партия кончается, когда за столом остался один игрок с картами — он
 * и есть дурак. Вышли все разом — ничья.
 * Вдвоём это прежнее правило: у кого-то кончились карты, значит остался один.
 *
 * В игре парами считают не людей, а пары: партия идёт, пока карты есть
 * у обеих пар. Поэтому игрок, оставшийся без карт при живом напарнике,
 * просто выходит из-за стола, а его пара продолжает играть. Проигрывают
 * оба из той пары, у которой карты остались, — даже если у одного из них
 * рука уже пуста: дурак тут не человек, а пара.
 */
function проверитьКонец(партия) {
  if (партия.колода.length > 0) return;

  if (партия.парами) {
    const сКартами = пары(партия).filter(function (пара) {
      return пара.some(function (имя) { return вИгре(партия, имя); });
    });
    if (сКартами.length > 1) return;    // карты есть у обеих пар — играем дальше
    записатьИтог(партия, сКартами.length === 0 ? [] : сКартами[0].slice());
    return;
  }

  const вживых = оставшиеся(партия);
  if (вживых.length > 1) return;
  записатьИтог(партия, вживых.slice());
}

/**
 * Кому достаётся ход. Названный игрок мог только что выйти из партии —
 * тогда ходит следующий за ним по кругу.
 * Это второе (вместе с «кто отбивается») место, где решается очерёдность.
 *
 * В игре парами есть разница: очередь принадлежит не человеку, а паре.
 * Вышел из партии тот, кому выпал ход, — ходит его напарник, а не сосед
 * по кругу. Иначе получалось так, на что и жаловался живой игрок: соперник
 * отбился последней картой, вышел — и ход доставался напарнику нападавшего,
 * то есть возвращался той же паре, которая только что нападала.
 * Вышли оба из пары — ход и правда идёт дальше по кругу.
 */
function назначитьХод(партия, игрок) {
  if (вИгре(партия, игрок)) { партия.атакует = игрок; return; }
  const напарникВышедшего = партнёр(партия, игрок);
  if (напарникВышедшего && вИгре(партия, напарникВышедшего)) {
    партия.атакует = напарникВышедшего;
    return;
  }
  партия.атакует = следующийВКруге(партия, игрок);
}

/**
 * Кому переходит ход после подхода.
 *
 * Отбился — ходит он сам: привычное правило и вдвоём, и компанией.
 * Взял — в обычной игре ход перешагивает через него и достаётся
 * следующему по кругу.
 *
 * А в игре парами нападавшая пара ход не отдаёт: раз соперник взял карты,
 * нападает второй из той же пары — напарник того, кто ходил. Так играют
 * по правилам, которые подтвердил владелец. Напарник уже вышел из партии —
 * ходит сам нападавший: пара всё равно своей очереди не теряет.
 */
function наследникХода(партия, защитник, защитникВзял) {
  if (!защитникВзял) return защитник;
  if (партия.парами) return партнёр(партия, партия.атакует) || партия.атакует;
  return следующийВКруге(партия, защитник);
}

/**
 * Закончить подход: карты со стола уходят в отбой либо к тому, кто берёт;
 * затем добор и передача хода. Кому достаётся ход, решает наследникХода —
 * в игре парами это правило своё.
 */
function завершитьПодход(партия) {
  if (партия.завершена) return false;
  const защитник = защищается(партия);
  const защитникВзял = партия.берёт;

  for (const пара of партия.стол) {
    if (защитникВзял) {
      партия.руки[защитник].push(пара.атака);
      if (пара.защита) партия.руки[защитник].push(пара.защита);
    } else {
      партия.отбой.push(пара.атака);
      if (пара.защита) партия.отбой.push(пара.защита);
    }
  }

  партия.стол = [];
  партия.берёт = false;
  партия.пасы = [];
  добрать(партия);
  // Кому ходить дальше, решаем до того, как узнаем выбывших: правило простое
  // и от них не зависит, а вот назначить ход вышедшему уже нельзя.
  const наследник = наследникХода(партия, защитник, защитникВзял);
  отметитьВыбывших(партия);
  назначитьХод(партия, наследник);
  упорядочитьРуку(партия, партия.игроки[0]);
  проверитьКонец(партия);
  return true;
}

/* ---------------------------------------------------------------------
   Бот. Три манеры игры — по выбранному уровню соперника:

   «обычный» — жадный расчёт: кроет самой мелкой подходящей картой,
               козырь придерживает, берёт, когда крыть нечем;
   «лёгкий»  — тот же бот, но время от времени ошибается, как новичок:
               бьёт козырем там, где хватило бы простой карты,
               и ходит случайной картой вместо самой мелкой;
   «сложный» — бережёт козыри всерьёз (за мелкую карту лучше возьмёт,
               чем потратит козырь), не отдаёт козыри тому, кто берёт,
               и помнит вышедшие карты: когда колода кончилась, он точно
               знает руку соперника и ходит тем, что тому не побить.
   --------------------------------------------------------------------- */

// Как часто лёгкий соперник играет не лучшей картой.
const ДОЛЯ_ОШИБОК_ЛЁГКОГО = 0.35;

/* Повадки сложного соперника подбирались замером — по 3000 партий против
   обычного бота на каждый вариант. Обычный выигрывает 40% партий; сложный
   со счётом карт и бережливостью к козырям — 49%, и ничьих вдвое меньше
   (10% против 21%). Ещё одну идею — «за мелкую карту лучше взять, чем крыть
   козырем» — замер отверг: с ней бот выигрывал только 38%, поэтому её тут нет. */

/** Из списка индексов руки выбрать индекс самой младшей карты. */
function индексМладшей(рука, индексы) {
  let лучший = индексы[0];
  for (const i of индексы) {
    if (рука[i].вес < рука[лучший].вес) лучший = i;
  }
  return лучший;
}

/** Из списка индексов руки выбрать индекс самой старшей карты. */
function индексСтаршей(рука, индексы) {
  let лучший = индексы[0];
  for (const i of индексы) {
    if (рука[i].вес > рука[лучший].вес) лучший = i;
  }
  return лучший;
}

/** Есть ли в руке ещё одна карта того же достоинства — такой картой хорошо ходить. */
function естьПара(рука, индекс) {
  for (let i = 0; i < рука.length; i++) {
    if (i !== индекс && рука[i].имя === рука[индекс].имя) return true;
  }
  return false;
}

/**
 * Какие карты могут быть у соперника. Считаем от обратного: вся колода
 * минус то, что бот видит своими глазами, — его рука, отбой и стол.
 * Пока в колоде есть карты, список получается «возможные», а когда
 * колода кончилась — это уже точная рука соперника.
 *
 * За столом втроём и больше в этот список попадают карты всех остальных
 * разом, а не одного отбивающегося. Бот от этого становится осторожнее,
 * чем нужно, но ошибок в правилах это не даёт — только манеру игры.
 */
function возможныеКартыСоперника(партия, игрок) {
  const видно = Object.create(null);
  const пометить = function (карта) { видно[карта.имя + карта.масть] = true; };
  for (const карта of партия.руки[игрок]) пометить(карта);
  for (const карта of партия.отбой) пометить(карта);
  for (const пара of партия.стол) {
    пометить(пара.атака);
    if (пара.защита) пометить(пара.защита);
  }
  const остальные = [];
  for (const карта of собратьКолоду(партия.размерКолоды)) {
    if (!видно[карта.имя + карта.масть]) остальные.push(карта);
  }
  return остальные;
}

/** Может ли соперник побить эту карту хоть чем-нибудь из возможных. */
function соперникПобьёт(партия, карта, чужие) {
  for (const чужая of чужие) {
    if (бьёт(чужая, карта, партия.козырь)) return true;
  }
  return false;
}

/** Самая мелкая карта, но при равных — та, к которой в руке есть пара: её потом подкинем. */
function мелкаяСОглядкойНаПару(рука, выбор) {
  let лучший = выбор[0];
  let лучшаяОценка = Infinity;
  for (const i of выбор) {
    const оценка = рука[i].вес - (естьПара(рука, i) ? 0.5 : 0);
    if (оценка < лучшаяОценка) {
      лучшаяОценка = оценка;
      лучший = i;
    }
  }
  return лучший;
}

/**
 * Чем ходит сложный соперник. Вернёт -1, если решил закончить подход.
 * Главная его сила — в концовке: когда колода пуста, он по отбою и по своей
 * руке точно знает карты соперника и кладёт то, что тому нечем крыть.
 */
function выборСложного(партия, игрок, годные, первыйХод) {
  const рука = партия.руки[игрок];
  const эндшпиль = партия.колода.length === 0;

  if (эндшпиль) {
    const чужие = возможныеКартыСоперника(партия, игрок);
    // Карта, которую сопернику нечем побить, — он вынужден будет взять.
    // Козырь здесь тоже в дело: в концовке он важнее бережливости.
    const неотбиваемые = годные.filter(function (i) {
      return !соперникПобьёт(партия, рука[i], чужие);
    });
    if (неотбиваемые.length > 0) return индексМладшей(рука, неотбиваемые);
    // Соперник и так берёт, а колоды больше нет: сбрасываем всё, чтобы
    // остаться с пустыми руками — это и есть победа.
    if (партия.берёт) return индексМладшей(рука, годные);
  }

  const некозырные = годные.filter(function (i) { return рука[i].масть !== партия.козырь; });
  if (некозырные.length > 0) return мелкаяСОглядкойНаПару(рука, некозырные);

  if (первыйХод) return индексМладшей(рука, годные);   // ходить всё равно надо
  // В руке одни козыри, а соперник берёт: отдавать их ему — расточительство,
  // лучше закончить подход.
  return -1;
}

/** Какую карту бот кладёт в атаку. Вернёт -1, если решил закончить подход. */
function выбратьКартуДляАтаки(партия, игрок, годные, первыйХод, сложность) {
  const рука = партия.руки[игрок];

  // Новичок время от времени кладёт что попало — бывает, что и козырь.
  if (сложность === 'лёгкий' && Math.random() < ДОЛЯ_ОШИБОК_ЛЁГКОГО) {
    return годные[Math.floor(Math.random() * годные.length)];
  }

  if (сложность === 'сложный') return выборСложного(партия, игрок, годные, первыйХод);

  const некозырные = годные.filter(function (i) { return рука[i].масть !== партия.козырь; });
  if (некозырные.length > 0) return индексМладшей(рука, некозырные);

  // В руке одни козыри: ходить всё равно надо, а берущему не жалко и козыря.
  if (первыйХод || партия.берёт) return индексМладшей(рука, годные);
  return -1;
}

/** Чем бот отбивается: список годных карт уже собран, надо выбрать одну. */
function выбратьКартуДляЗащиты(партия, игрок, годные, сложность) {
  const рука = партия.руки[игрок];

  // Новичок хватается за самую крупную карту, часто зря тратит козырь.
  if (сложность === 'лёгкий' && Math.random() < ДОЛЯ_ОШИБОК_ЛЁГКОГО) {
    return индексСтаршей(рука, годные);
  }

  // Бьём самой мелкой подходящей, козырь — только когда другого нет.
  const некозырные = годные.filter(function (i) { return рука[i].масть !== партия.козырь; });
  return индексМладшей(рука, некозырные.length > 0 ? некозырные : годные);
}

/**
 * Бот больше не кладёт карту. Вдвоём это сразу «Бито», а за столом побольше
 * подход продолжится: право подкинуть перейдёт следующему по кругу.
 */
function отказатьсяПодкидывать(партия, игрок, первыйХод) {
  пас(партия, игрок);
  if (первыйХод) return 'пас';
  return партия.стол.length === 0 ? 'бито' : 'не подкидывает';
}

/** Один ход бота в роли атакующего (первая карта, подкидывание или «Бито»). */
function атакаБота(партия, игрок, сложность) {
  const рука = партия.руки[игрок];
  const первыйХод = партия.стол.length === 0;

  const годные = [];
  for (let i = 0; i < рука.length; i++) {
    if (можноПоложить(партия, рука[i])) годные.push(i);
  }
  // Нечего класть: отказываемся подкидывать дальше. При пустом столе такое
  // возможно, только когда партия и так уже фактически доиграна.
  if (годные.length === 0) return отказатьсяПодкидывать(партия, игрок, первыйХод);

  const индекс = выбратьКартуДляАтаки(партия, игрок, годные, первыйХод, сложность);
  if (индекс === -1) return отказатьсяПодкидывать(партия, игрок, первыйХод);

  положитьВАтаку(партия, игрок, индекс);
  return первыйХод ? 'ходит' : 'подкидывает';
}

/**
 * Чем бот переведёт ход (только в переводном дураке). Вернёт -1, если
 * переводить нечем или незачем.
 *
 * Козырем не переводим никогда: козырь дороже тем, что им можно отбиться,
 * а перевести обычно есть чем и без него.
 */
function выборПеревода(партия, игрок) {
  if (!партия.переводной) return -1;
  const рука = партия.руки[игрок];
  const годные = [];
  for (let i = 0; i < рука.length; i++) {
    if (рука[i].масть === партия.козырь) continue;
    if (можноПеревести(партия, рука[i])) годные.push(i);
  }
  if (годные.length === 0) return -1;
  return индексМладшей(рука, годные);
}

/** Один ход бота в роли защищающегося: перевести, отбиться или взять. */
function защитаБота(партия, игрок, сложность) {
  const рука = партия.руки[игрок];

  // Перевод выгоднее защиты: карта уходит из руки, а отбиваться будет сосед.
  const переводом = выборПеревода(партия, игрок);
  if (переводом !== -1) {
    перевести(партия, переводом);
    return 'переводит';
  }

  let индексПары = -1;
  for (let i = 0; i < партия.стол.length; i++) {
    if (!партия.стол[i].защита) { индексПары = i; break; }
  }
  if (индексПары === -1) return 'нечего';

  const атака = партия.стол[индексПары].атака;
  const годные = [];
  for (let i = 0; i < рука.length; i++) {
    if (бьёт(рука[i], атака, партия.козырь)) годные.push(i);
  }
  if (годные.length === 0) {
    объявитьБеру(партия);
    return 'беру';
  }

  const индекс = выбратьКартуДляЗащиты(партия, игрок, годные, сложность);

  отбить(партия, индексПары, индекс);
  return 'отбивается';
}

/**
 * Сделать за игрока один ход по правилам бота.
 * Уровень можно передать третьим доводом — иначе берётся уровень партии.
 * Возвращает короткое название действия — оно нужно автотесту и отладке.
 */
function ходБота(партия, игрок, сложность) {
  if (партия.завершена) return 'конец';
  if (ктоХодит(партия) !== игрок) return 'не его ход';
  const уровень = проверитьСложность(сложность || партия.сложность);
  return фаза(партия) === 'защита'
    ? защитаБота(партия, игрок, уровень)
    : атакаБота(партия, игрок, уровень);
}

