/* =====================================================================
   Экран «Профиль» — всё, что человек знает про себя, одним экраном.

   Чем он отличается от двух соседних экранов:
     — «Рейтинг игроков» отвечает «где я среди остальных» (чужие строки);
     — «Как я играю» считает партии ОДНОЙ игры в самом телефоне;
     — «Профиль» (этот файл) — про меня во всём сборнике сразу: имя, место,
       очки по каждой игре и серия дней. «Как я играю» отсюда — дверь вниз.

   Одна дверь наружу:
       window.ЭкранПрофиля.открыть('дурак')   // игра страницы

   Разметки в html нет ни на одной странице — экран строит её сам, теми же
   приёмами, что js/рейтинг-экран.js (см. «построитьРазметкуРейтингаИгроков»):
   только структура, id, классы, текст и числа. Размеры, цвета и отступы —
   дело style.css, из кода вида не задаём.

   Данные этот файл сам с сервера не просит: он спрашивает соседа
   (window.ЭкранРейтинга.мойПрофиль и .игры). Второй копии запроса и второго
   списка игр в сборнике быть не должно — они однажды разойдутся с первыми.
   Соседа может и не быть (старая страница, файл не подключён) — тогда экран
   всё равно открывается: имя, фото и серия у него свои, а вместо очков
   стоит одна честная строка.

   Правило про текст то же, что у рейтинга: всё, что пришло с сервера или
   от Telegram, кладётся только через textContent. Ни одного innerHTML.
   ===================================================================== */

'use strict';

(function () {

  /* Имена узлов — в одном месте, как у рейтинга: договор имён из
     штаб/план-профиль-по-макету.md, §3. По ним же оформитель пишет css
     и проверка ищет узлы. */
  const ЭКРАН = 'экран-профиля-игрока';
  const УЗЕЛ_КАРТОЧКА = 'профиль-карточка';
  const УЗЕЛ_ОЧКИ = 'профиль-очки';
  const УЗЕЛ_СЕРИЯ = 'профиль-серия';
  const КНОПКА_НАЗАД = 'кнопка-профиля-назад';
  const КНОПКА_КАК_Я_ИГРАЮ = 'кнопка-профиля-как-я-играю';
  const КНОПКА_ПОВТОРИТЬ = 'кнопка-профиля-повторить';
  /* Обёртка, внутри которой живёт ЛИБО блок очков, ЛИБО одно из его
     состояний (загрузка, беда, честная строка). Своего id у неё нет
     нарочно: договор имён требует, чтобы при отсутствии данных не было
     самого узла «профиль-очки», — держать его пустым нельзя. */
  const КЛАСС_МЕСТА_ОЧКОВ = 'профиль-очки-место';

  /* Разделитель тысяч — та же заготовка, что в js/рейтинг-экран.js:
     «24 860» вместо «24860» (пробел неразрывный, его ставит сам Intl). */
  const ЧИСЛА_ПО_РУССКИ = new Intl.NumberFormat('ru-RU');

  /* Какая игра у страницы, где мы стоим («дурак» на index.html, «шашки»
     на шашки.html и так далее). Нужна только кнопке «Как я играю»: счёт
     там всегда про одну игру. */
  let играСтраницы = 'дурак';

  /* Куда возвращает «‹». Память своя, как у экрана «Как я играю»
     (js/рейтинг-экран.js, «назадИзСчёта»): профиль открывают с разных
     мест, и общая память возврата из js/game.js о нём ничего не знает. */
  let откудаПришли = 'экран-меню';

  /* Номер последнего запроса данных: человек может нажать «Повторить»
     дважды, и старый ответ не должен дорисовываться поверх нового. */
  let номерЗапроса = 0;

  /* То же для серии дней — она приходит своим, отдельным обещанием. */
  let поколениеСерии = 0;

  /* -------------------------------------------------------------------
     Чистые функции: решают, ЧТО показать, и страницу не трогают вовсе.
     Их же проверяет tests/профиль-экран-случаи.js прямо в node.
     ------------------------------------------------------------------- */

  /** Число из ответа сервера. Мусор — null, а не «NaN» на экране. */
  function число(что) {
    if (что === null || что === undefined || что === '') return null;
    const н = Number(что);
    return isFinite(н) ? н : null;
  }

  /** Число по-русски: «24 860». Не число — ноль, а не пустота. */
  function округлить(что) {
    const н = Number(что) || 0;
    return ЧИСЛА_ПО_РУССКИ.format(Number.isInteger(н) ? н : Math.round(н * 10) / 10);
  }

  /**
   * Буквы вместо фотографии. Правило то же, что в таблице рейтинга
   * (js/рейтинг-экран.js, «инициалы»): два слова — первые буквы обоих,
   * одно слово — две его первые буквы. Копия маленькая нарочно: сосед
   * эту функцию наружу не отдаёт, а тянуть ради двух строк общий файл
   * дороже, чем повторить правило с ссылкой на источник.
   */
  function инициалы(имя) {
    const слова = String(имя || '').trim().split(/\s+/).filter(Boolean);
    if (!слова.length) return '';
    if (слова.length === 1) return слова[0].slice(0, 2).toUpperCase();
    return (слова[0].charAt(0) + слова[1].charAt(0)).toUpperCase();
  }

  /** «день», «дня», «дней» — по числу (правило из js/game.js, «словоДней»). */
  function словоДней(сколько) {
    const двеПоследние = сколько % 100;
    const последняя = сколько % 10;
    if (двеПоследние >= 11 && двеПоследние <= 14) return 'дней';
    if (последняя === 1) return 'день';
    if (последняя >= 2 && последняя <= 4) return 'дня';
    return 'дней';
  }

  /**
   * Строка про серию дней. Правило слово в слово то же, что у дурака
   * (js/game.js, «словаОСерииВПрофиле», строки 10186–10193): единица —
   * не серия, вчера играли, а сегодня нет — тихое приглашение без
   * давления. Пустая строка — показывать нечего.
   */
  function словаОСерииВПрофиле(серия) {
    const дней = серия ? Number(серия.серия) || 0 : 0;
    if (дней < 2) return '';
    if (серия.сегодняОтмечен === true) return дней + ' ' + словоДней(дней) + ' подряд';
    return 'Вчера играли — сыграйте сегодня, чтобы не прервать серию из ' + дней;
  }

  /**
   * Человеческие слова о беде. В поле «беда» приходит либо системный код
   * дороги до сервера ('связь', 'нет-адреса', 'плохой-адрес' — те же, что
   * у таблицы рейтинга), либо 'отказ-сервера', либо ЖИВОЙ текст причины,
   * который написал сам сервер (js/рейтинг-экран.js, «мойПрофиль»: при
   * ответе «ок: false» туда кладётся «причина»). Живой текст показываем
   * как есть — сервер объясняет точнее нас. Пусто или голый системный код
   * — обезличенное «не прочиталось», код человеку не показываем.
   */
  function словаОБеде(код) {
    const текст = String(код == null ? '' : код).trim();
    if (текст === 'нет-адреса') return 'Игра не знает, где сервер с рейтингом';
    if (текст === 'плохой-адрес') return 'Адрес сервера записан неправильно';
    if (текст === 'связь') return 'Сервер с рейтингом не отвечает';
    if (текст === '' || текст === 'отказ-сервера') return 'Очки пока не прочитались';
    return текст;
  }

  /**
   * Что стоит в карточке на месте места. Новичок (сервер нас не знает
   * или места ещё нет) — прочерк, а не «0 место»: ноль местом не бывает.
   */
  function текстМеста(данные) {
    if (!данные || данные.узналиВас !== true) return '—';
    const место = число(данные.место);
    if (место === null || место <= 0) return '—';
    const всего = число(данные.всего);
    return всего !== null && всего > 0 ? место + ' место из ' + всего : место + ' место';
  }

  /**
   * Строки блока «Ваши очки по играм»: по строке на КАЖДУЮ игру сборника,
   * даже если человек в неё ещё не играл (тогда ноль) — так на макете
   * владельца. Порядок — порядок реестра игр соседа, своего у нас нет.
   *
   * Пункт «Все игры» из реестра сюда не попадает: это не игра, а сумма,
   * и своя строка «Всего» внизу блока уже есть.
   */
  function строкиОчков(игры, поИграм) {
    const своиОчки = Object.create(null);
    const список = Array.isArray(поИграм) ? поИграм : [];
    for (const запись of список) {
      if (!запись || typeof запись !== 'object') continue;
      const ключ = String(запись.игра || '');
      /* Повтор одной игры в ответе — берём первую запись, а не сумму:
         так строка предсказуема, что бы ни прислал сервер. */
      if (!ключ || Object.prototype.hasOwnProperty.call(своиОчки, ключ)) continue;
      своиОчки[ключ] = число(запись.очки) || 0;
    }
    return (Array.isArray(игры) ? игры : [])
      .filter(function (и) { return и && и.ключ && и.ключ !== 'все'; })
      .map(function (и) {
        return {
          ключ: и.ключ,
          подпись: String(и.подпись || и.ключ),
          очки: своиОчки[и.ключ] || 0
        };
      });
  }

  /**
   * «Всего» — сумма ровно тех строк, что человек видит. Считать по
   * ответу сервера отдельно нельзя: если сервер пришлёт очки за игру,
   * которой в реестре нет, итог перестал бы сходиться со строками.
   */
  function суммаОчков(строки) {
    return (Array.isArray(строки) ? строки : []).reduce(function (сумма, с) {
      return сумма + (Number(с && с.очки) || 0);
    }, 0);
  }

  /* -------------------------------------------------------------------
     Соседние двери. Каждой может не быть — ни одна проверка не лишняя:
     на четырёх страницах сборника порядок подключения файлов разный.
     ------------------------------------------------------------------- */

  /** Окно страницы или null (в node при проверке чистых функций его нет). */
  function окно() {
    return typeof window !== 'undefined' ? window : null;
  }

  /** Дверь экрана рейтинга — источник данных профиля. */
  function дверьРейтинга() {
    const о = окно();
    return (о && о.ЭкранРейтинга) ? о.ЭкранРейтинга : null;
  }

  /** Список игр сборника — копия реестра соседа; нет двери — пусто. */
  function игрыСборника() {
    const дверь = дверьРейтинга();
    if (!дверь || typeof дверь.игры !== 'function') return [];
    try {
      const список = дверь.игры();
      return Array.isArray(список) ? список : [];
    } catch (сбой) {
      return [];
    }
  }

  /** Имя игрока из Telegram; вне Telegram — пустая строка. */
  function имяИгрока() {
    const о = окно();
    try {
      if (о && о.Телеграм && typeof о.Телеграм.имяИгрока === 'function') {
        return String(о.Телеграм.имяИгрока() || '').trim();
      }
    } catch (сбой) { /* нет Telegram — покажем без имени */ }
    return '';
  }

  /** Адрес фотографии игрока; нет фото — пустая строка. */
  function фотоИгрока() {
    const о = окно();
    try {
      if (о && о.Телеграм && typeof о.Телеграм.фотоИгрока === 'function') {
        return String(о.Телеграм.фотоИгрока() || '').trim();
      }
    } catch (сбой) { /* нет Telegram — останутся инициалы */ }
    return '';
  }

  /**
   * Спросить данные профиля. Обещание не срывается никогда: беда со
   * связью — это обычный ответ с пометкой, а не исключение.
   * Ответ null означает особое: двери к данным нет вовсе.
   */
  function спроситьПрофиль() {
    const дверь = дверьРейтинга();
    if (!дверь || typeof дверь.мойПрофиль !== 'function') return Promise.resolve(null);
    let ответ;
    try {
      ответ = дверь.мойПрофиль();
    } catch (сбой) {
      return Promise.resolve({ беда: 'связь' });
    }
    return Promise.resolve(ответ).then(
      function (данные) {
        return (данные && typeof данные === 'object') ? данные : { беда: 'связь' };
      },
      function () { return { беда: 'связь' }; }
    );
  }

  /** Сводка серии дней подряд; нет двери или сбой — null. */
  function спроситьСерию() {
    const о = окно();
    if (!о || !о.Рейтинг || typeof о.Рейтинг.серияДней !== 'function') return Promise.resolve(null);
    let ответ;
    try {
      ответ = о.Рейтинг.серияДней();
    } catch (сбой) {
      return Promise.resolve(null);
    }
    return Promise.resolve(ответ).then(
      function (серия) { return (серия && typeof серия === 'object') ? серия : null; },
      function () { return null; }
    );
  }

  /* -------------------------------------------------------------------
     Рисование. Только отсюда трогаем страницу.
     ------------------------------------------------------------------- */

  function узел(id) {
    return typeof document !== 'undefined' ? document.getElementById(id) : null;
  }

  function очистить(место) {
    if (!место) return;
    while (место.firstChild) место.removeChild(место.firstChild);
  }

  function рамка(класс) {
    const н = document.createElement('div');
    if (класс) н.className = класс;
    return н;
  }

  function контейнер(id, класс) {
    const н = рамка(класс);
    н.id = id;
    return н;
  }

  function абзац(текстСтроки, класс) {
    const н = document.createElement('p');
    н.className = класс || 'подпись';
    н.textContent = текстСтроки;
    return н;
  }

  function ячейка(текстЯчейки, класс) {
    const н = document.createElement('span');
    н.className = класс;
    н.textContent = текстЯчейки;
    return н;
  }

  function кнопкаЭл(id, текст, класс, действие) {
    const н = document.createElement('button');
    н.type = 'button';
    if (id) н.id = id;
    н.className = класс;
    н.textContent = текст;
    if (действие) н.addEventListener('click', действие);
    return н;
  }

  /** Куда вставлять построенный экран — общий корень страницы. */
  function хозяинЭкранов() {
    if (typeof document === 'undefined') return null;
    const хозяин = document.getElementById('приложение') || document.body;
    return (хозяин && typeof хозяин.appendChild === 'function') ? хозяин : null;
  }

  /**
   * Значок игры — картинка из img/рейтинг/, тем же приёмом, что у кнопки
   * выбора игры в рейтинге («значокВыбраннойИгры»): обычный файл и «@2x»
   * для плотных экранов, выбирает сам браузер по srcset.
   */
  function значокИгры(ключ) {
    const значок = document.createElement('img');
    значок.className = 'профиль-очки__значок';
    const путь = 'img/рейтинг/' + ключ;
    значок.src = путь + '.png';
    значок.srcset = путь + '.png 1x, ' + путь + '@2x.png 2x';
    /* Пустой alt нарочно: рядом стоит название игры словами, и читалка
       экрана произнесла бы его дважды. */
    значок.alt = '';
    return значок;
  }

  /**
   * Стрелка движения места за сутки — тот же узел и те же классы, что
   * в строке таблицы рейтинга («узелДвижения»), чтобы вид у стрелки
   * в сборнике был один. Поля может не быть вовсе (старый сервер) —
   * тогда и узла нет, а не пустая метка.
   */
  function узелДвижения(данные) {
    if (!данные || !данные.движение) return null;
    const сдвиг = число(данные.сдвиг);
    const сдвигГоден = сдвиг !== null && сдвиг >= 0;
    const н = document.createElement('span');
    if (данные.движение === 'выросло' && сдвигГоден) {
      н.className = 'профиль-карточка__движение рейтинг-движение рейтинг-движение--вверх';
      н.textContent = '↑ ' + сдвиг;
    } else if (данные.движение === 'упало' && сдвигГоден) {
      н.className = 'профиль-карточка__движение рейтинг-движение рейтинг-движение--вниз';
      н.textContent = '↓ ' + сдвиг;
    } else if (данные.движение === 'безИзменений' || данные.движение === 'нетДанных' ||
               данные.движение === 'выросло' || данные.движение === 'упало') {
      н.className = 'профиль-карточка__движение рейтинг-движение рейтинг-движение--нет';
      н.textContent = '—';
    } else {
      return null;
    }
    return н;
  }

  /** Пустой узел нижней полосы вкладок — набор «профиль». */
  function узелНижнихВкладок() {
    const н = document.createElement('nav');
    н.className = 'нижние-вкладки';
    н.setAttribute('data-вкладки', 'профиль');
    return н;
  }

  /**
   * Заполнить полосу кнопками — ЛЕНИВО, в момент открытия экрана: на
   * разных страницах этот файл подключён раньше или позже соседей, и при
   * разборе страницы двери window.НижниеВкладки может ещё не быть. Набор
   * «профиль» заводит другой этап — пока его нет, сосед честно ругнётся
   * в консоль и оставит полосу пустой, а экран всё равно работает.
   */
  function заполнитьНижниеВкладки() {
    const экран = узел(ЭКРАН);
    const полоса = экран ? экран.querySelector('.нижние-вкладки') : null;
    const о = окно();
    if (!полоса || !о || !о.НижниеВкладки || typeof о.НижниеВкладки.заполнитьПолосу !== 'function') return;
    try {
      о.НижниеВкладки.заполнитьПолосу(полоса);
    } catch (сбой) { /* нет набора «профиль» — полоса останется пустой */ }
  }

  /* -------------------------------------------------------------------
     Своя разметка: гнёзд в html нет ни на одной странице.
     ------------------------------------------------------------------- */

  /** Карточка игрока: аватар, имя, место, очки. Числа появятся позже. */
  function построитьКарточку() {
    const карточка = контейнер(УЗЕЛ_КАРТОЧКА, 'профиль-карточка');
    const аватар = рамка('профиль-карточка__аватар');
    аватар.appendChild(ячейка('', 'профиль-карточка__инициалы'));
    карточка.appendChild(аватар);
    карточка.appendChild(ячейка('', 'профиль-карточка__имя'));
    карточка.appendChild(ячейка('', 'профиль-карточка__место'));
    карточка.appendChild(ячейка('', 'профиль-карточка__очки'));
    /* Узла движения здесь нет: он появляется рядом с очками только когда
       сервер и правда прислал стрелку (см. «заполнитьКарточку»). */
    return карточка;
  }

  /** Построить весь экран «Профиль» и вставить его в страницу. */
  function построитьРазметкуПрофиля() {
    const хозяин = хозяинЭкранов();
    if (!хозяин) return null;

    const секция = document.createElement('section');
    секция.id = ЭКРАН;
    секция.className = 'экран';

    const шапка = рамка('профиль-шапка');
    /* «‹» — та же кнопка, что у рейтинга: внутри Telegram её прячет
       правило html.в-телеграме в style.css, там за возврат отвечает
       системная стрелка (её привязываем в «открыть»). */
    const назад = кнопкаЭл(КНОПКА_НАЗАД, '‹', 'профиль-шапка__назад', назадИзПрофиля);
    назад.setAttribute('aria-label', 'Назад');
    шапка.appendChild(назад);
    const название = document.createElement('h2');
    название.className = 'заголовок профиль-шапка__название';
    название.textContent = 'Профиль';
    шапка.appendChild(название);
    секция.appendChild(шапка);

    секция.appendChild(построитьКарточку());
    /* Обёртка под очки: её содержимое меняется от состояния к состоянию
       (загрузка, беда, блок очков, честная строка). */
    секция.appendChild(рамка(КЛАСС_МЕСТА_ОЧКОВ));
    const серия = абзац('', 'профиль-серия скрыт');
    серия.id = УЗЕЛ_СЕРИЯ;
    секция.appendChild(серия);
    секция.appendChild(кнопкаЭл(КНОПКА_КАК_Я_ИГРАЮ, 'Как я играю', 'кнопка кнопка--мелкая',
      открытьКакЯИграю));
    /* Полоса вкладок — последним узлом экрана, как на других домашних
       экранах сборника. Кнопки в неё кладёт «заполнитьНижниеВкладки». */
    секция.appendChild(узелНижнихВкладок());

    хозяин.appendChild(секция);
    return секция;
  }

  /** Экран есть на странице или строим его сейчас. */
  function убедитьсяЧтоЭкранЕсть() {
    if (typeof document === 'undefined') return null;
    return document.getElementById(ЭКРАН) || построитьРазметкуПрофиля();
  }

  /* -------------------------------------------------------------------
     Заполнение: имя и фото, карточка, очки, серия
     ------------------------------------------------------------------- */

  /**
   * Имя, инициалы и фото. Показываются всегда — они из телефона, а не
   * с сервера, и от беды со связью не зависят. Имени нет (игра открыта
   * не в Telegram) — пишем нейтральное «Игрок», пустой строки на экране
   * не оставляем.
   */
  function освежитьИмяИФото() {
    const карточка = узел(УЗЕЛ_КАРТОЧКА);
    if (!карточка) return;
    /* Одна переменная на оба места: инициалы должны считаться от ТОГО ЖЕ
       имени, что показано в карточке, иначе при пустом имени (не в
       Telegram) кружок аватара остаётся без букв — имя подменили
       запасным «Игрок», а инициалы нет. */
    const имяДляПоказа = имяИгрока() || 'Игрок';
    const узелИмени = карточка.querySelector('.профиль-карточка__имя');
    if (узелИмени) узелИмени.textContent = имяДляПоказа;
    const узелБукв = карточка.querySelector('.профиль-карточка__инициалы');
    if (узелБукв) узелБукв.textContent = инициалы(имяДляПоказа);
    поставитьФото(карточка.querySelector('.профиль-карточка__аватар'));
  }

  /**
   * Фото игрока кладём в CSS-переменную (как «поставитьФото» у рейтинга):
   * из js — только данные, картинку рисует style.css. Ждём загрузки, а не
   * ставим сразу: битый адрес оставил бы пустой кружок вместо инициалов.
   * В node картинок нет вовсе — тогда ставим без ожидания.
   */
  function поставитьФото(аватар) {
    if (!аватар) return;
    const адрес = фотоИгрока();
    if (!адрес) {
      аватар.classList.remove('профиль-карточка__аватар--фото');
      аватар.style.removeProperty('--фото-аватара');
      return;
    }
    const показать = function () {
      аватар.style.setProperty('--фото-аватара', 'url("' + адрес + '")');
      if (аватар.style.getPropertyValue('--фото-аватара').trim() === '') return;
      аватар.classList.add('профиль-карточка__аватар--фото');
    };
    const о = окно();
    if (!о || typeof о.Image !== 'function') { показать(); return; }
    const картинка = new о.Image();
    картинка.onload = показать;
    картинка.onerror = function () { /* сеть подвела — остаются инициалы */ };
    картинка.src = адрес;
  }

  /** Убрать прежнюю стрелку движения — она рисуется заново на каждый ответ. */
  function убратьДвижение(карточка) {
    const старая = карточка.querySelector('.профиль-карточка__движение');
    if (старая) старая.remove();
  }

  /**
   * Место и очки в карточке. Данные null — двери к ним нет или ещё ждём:
   * тогда прочерки, а не выдуманные нули. Новичок — прочерк на месте
   * и честный ноль очков: сыграно и правда ноль.
   */
  function заполнитьКарточку(данные) {
    const карточка = узел(УЗЕЛ_КАРТОЧКА);
    if (!карточка) return;
    убратьДвижение(карточка);
    const узелМеста = карточка.querySelector('.профиль-карточка__место');
    const узелОчков = карточка.querySelector('.профиль-карточка__очки');
    if (!данные || данные.беда) {
      if (узелМеста) узелМеста.textContent = '—';
      if (узелОчков) узелОчков.textContent = '—';
      return;
    }
    if (узелМеста) узелМеста.textContent = текстМеста(данные);
    if (узелОчков) узелОчков.textContent = округлить(число(данные.очки) || 0);
    const стрелка = узелДвижения(данные);
    if (стрелка) карточка.appendChild(стрелка);
  }

  /** Карточка, пока ответа нет. */
  function показатьОжиданиеВКарточке() {
    const карточка = узел(УЗЕЛ_КАРТОЧКА);
    if (!карточка) return;
    убратьДвижение(карточка);
    const узелМеста = карточка.querySelector('.профиль-карточка__место');
    const узелОчков = карточка.querySelector('.профиль-карточка__очки');
    if (узелМеста) узелМеста.textContent = 'Загружаем…';
    if (узелОчков) узелОчков.textContent = '—';
  }

  /** Обёртка, куда кладётся блок очков или его состояние. */
  function местоДляОчков() {
    const экран = узел(ЭКРАН);
    return экран ? экран.querySelector('.' + КЛАСС_МЕСТА_ОЧКОВ) : null;
  }

  /** Одна строка блока — кнопка в рейтинг этой игры, как на макете. */
  function строкаИгры(строка) {
    const кнопка = document.createElement('button');
    кнопка.type = 'button';
    кнопка.className = 'профиль-очки__строка';
    /* Метка нужна не только клику: по ней проверка и человек из отладки
       видят, про какую игру строка, не разбирая подпись. */
    кнопка.setAttribute('data-игра', строка.ключ);
    кнопка.appendChild(значокИгры(строка.ключ));
    кнопка.appendChild(ячейка(строка.подпись, 'профиль-очки__игра'));
    кнопка.appendChild(ячейка(округлить(строка.очки), 'профиль-очки__число'));
    кнопка.addEventListener('click', function () { открытьРейтингИгры(строка.ключ); });
    return кнопка;
  }

  /** Весь блок «Ваши очки по играм» со строкой «Всего» внизу. */
  function блокОчков(строки) {
    const блок = контейнер(УЗЕЛ_ОЧКИ, 'профиль-очки');
    блок.appendChild(абзац('Ваши очки по играм', 'профиль-очки__заголовок'));
    for (const строка of строки) блок.appendChild(строкаИгры(строка));
    const итог = рамка('профиль-очки__итог');
    итог.appendChild(ячейка('Всего', 'профиль-очки__итог-подпись'));
    итог.appendChild(ячейка(округлить(суммаОчков(строки)), 'профиль-очки__итог-число'));
    блок.appendChild(итог);
    return блок;
  }

  /**
   * Единственное место, где решается, что стоит под карточкой.
   * Случаи по порядку: ждём ответ · беда с кнопкой «Повторить» ·
   * честная строка, если очков нам никто не даёт · новичок (сервер нас
   * не знает — во всех играх честный ноль) · обычный блок очков.
   */
  function показатьОчки(данные) {
    const место = местоДляОчков();
    if (!место) return;
    очистить(место);
    if (данные === 'ждём') {
      место.appendChild(абзац('Загружаем…', 'таблица__пусто'));
      return;
    }
    if (данные && данные.беда) {
      место.appendChild(абзац(словаОБеде(данные.беда), 'таблица__пусто'));
      место.appendChild(кнопкаЭл(КНОПКА_ПОВТОРИТЬ, 'Повторить', 'кнопка кнопка--мелкая',
        обновитьДанные));
      return;
    }
    const игры = игрыСборника();
    /* Данных нет вовсе (соседнего файла на странице нет) или реестр игр
       пуст — рисовать нечего, и выдумывать нули нечестно. */
    if (!данные || !игры.length) {
      место.appendChild(строкаБезОчков());
      return;
    }
    /* Новичок: сервер нас не знает (или игра открыта не в Telegram, где
       рейтинг не ведётся вовсе). «поИграм» он в этом случае не присылает,
       но это не старый сервер: партий и правда ноль в каждой игре —
       так и показываем, по нулю в строке. */
    if (данные.узналиВас !== true) {
      место.appendChild(блокОчков(строкиОчков(игры, [])));
      return;
    }
    /* Старый сервер: нас узнал, а поля «поИграм» не знает. Нулей тут
       рисовать нельзя — очки у человека есть, мы их просто не видим. */
    if (!Array.isArray(данные.поИграм)) {
      место.appendChild(строкаБезОчков());
      return;
    }
    место.appendChild(блокОчков(строкиОчков(игры, данные.поИграм)));
  }

  /** Одна строка вместо блока очков, когда очков по играм нам не дают. */
  function строкаБезОчков() {
    return абзац('Очки по играм появятся после обновления', 'таблица__пусто');
  }

  /** Строка серии дней. Нет серии (или единица) — строки нет вовсе. */
  function освежитьСерию() {
    const узелСерии = узел(УЗЕЛ_СЕРИЯ);
    if (!узелСерии) return;
    const моё = ++поколениеСерии;
    спроситьСерию().then(function (серия) {
      if (моё !== поколениеСерии) return;
      const слова = словаОСерииВПрофиле(серия);
      узелСерии.textContent = слова;
      узелСерии.classList.toggle('скрыт', !слова);
      /* «Вчера играли — сыграйте сегодня»: оформление рисует это
         приглашением, а не тревогой (то же, что у дурака). */
      узелСерии.classList.toggle('профиль-серия--вчера',
        Boolean(слова) && !(серия && серия.сегодняОтмечен === true));
    });
  }

  /* -------------------------------------------------------------------
     Двери наружу и переходы
     ------------------------------------------------------------------- */

  /** Спросить данные заново и перерисовать всё, что от них зависит. */
  function обновитьДанные() {
    показатьОжиданиеВКарточке();
    показатьОчки('ждём');
    номерЗапроса += 1;
    const моё = номерЗапроса;
    спроситьПрофиль().then(function (данные) {
      // Человек успел нажать «Повторить» — этот ответ уже не последний.
      if (моё !== номерЗапроса) return;
      заполнитьКарточку(данные);
      показатьОчки(данные);
    });
  }

  /** Строка игры нажата — открываем рейтинг именно этой игры. */
  function открытьРейтингИгры(ключ) {
    const дверь = дверьРейтинга();
    if (дверь && typeof дверь.открыть === 'function') дверь.открыть(ключ);
  }

  /** Кнопка внизу — «Как я играю» про игру этой страницы. */
  function открытьКакЯИграю() {
    const дверь = дверьРейтинга();
    if (дверь && typeof дверь.открытьСчёт === 'function') дверь.открытьСчёт(играСтраницы);
  }

  /**
   * Показать экран. Если страница умеет переключать экраны сама
   * (js/game.js через window.ИграПоСети), заходим её дверью: она гасит
   * заодно ленту, панель знаков и отложенную плашку итога.
   */
  function показатьЭкран(id) {
    const о = окно();
    if (о && о.ИграПоСети && typeof о.ИграПоСети.экран === 'function') {
      о.ИграПоСети.экран(id);
      return;
    }
    for (const экран of document.querySelectorAll('.экран')) {
      экран.classList.toggle('экран--виден', экран.id === id);
    }
  }

  /** Какой экран открыт прямо сейчас — чтобы «‹» вернул туда, откуда пришли. */
  function текущийЭкран() {
    const открытый = document.querySelector('.экран.экран--виден');
    return (открытый && открытый.id) || 'экран-меню';
  }

  /** Системная стрелка Telegram делает тот же шаг, что и «‹» на экране. */
  function попытатьсяПривязатьСтрелку(действие) {
    const о = окно();
    try {
      if (о && о.Телеграм && typeof о.Телеграм.показатьСтрелку === 'function') {
        о.Телеграм.показатьСтрелку(действие);
      }
    } catch (сбой) { /* нет Telegram — на экране есть своя «‹» */ }
  }

  /** Шаг назад — общий для кнопки «‹» и для стрелки Telegram. */
  function назадИзПрофиля() {
    const о = окно();
    /* Общая дверь возврата живёт в js/game.js (на страницах шашек,
       шахмат и нард её нет). Если дверь есть — уходим ею же, что и
       стрелка Telegram: иначе у «Назад» получаются две разные памяти,
       и они расходятся после второго служебного экрана подряд (то же
       замечание ревьюера, что и у «назадИзРейтинга» в
       js/рейтинг-экран.js). Нет двери — запасной путь: своя память.
       Перед уходом освежаем общую память СВОЕЙ (откудаПришли): пока
       профиль был открыт, общую могла сбросить чужая дверь (например
       «Как я играю» → своё «Назад» в game.js) — тогда общая память
       снова верна и указывает туда, откуда на самом деле пришли. */
    if (о && typeof о.вернутьсяОткудаПришли === 'function') {
      if (typeof о.запомнитьМестоВозврата === 'function' && откудаПришли) {
        о.запомнитьМестоВозврата(откудаПришли);
      }
      о.вернутьсяОткудаПришли();
      return;
    }
    показатьЭкран(откудаПришли);
    /* Профиль — общий экран, он перекрыл стрелку страницы, с которой
       пришли. Уходя, возвращаем её обратно, иначе стрелка так и осталась
       бы делать «назад из профиля» (тот же приём, что «назадИзСчёта»
       в js/рейтинг-экран.js). */
    try {
      if (о && о.Телеграм && typeof о.Телеграм.вернутьПрежнююСтрелку === 'function') {
        о.Телеграм.вернутьПрежнююСтрелку();
      }
    } catch (сбой) { /* нет двери — своя кнопка «‹» на экране есть */ }
  }

  /**
   * Открыть профиль. Единственная дверь наружу.
   * «игра» — игра страницы: 'дурак' на index.html, 'шашки', 'шахматы',
   * 'нарды' на своих. Нужна только кнопке «Как я играю».
   */
  function открыть(игра) {
    if (typeof document === 'undefined') return;
    const ключ = String(игра || '').trim();
    if (ключ) играСтраницы = ключ;
    /* Запоминаем, откуда пришли, ДО показа своего экрана — иначе «‹»
       вернул бы человека на этот же профиль. */
    const было = текущийЭкран();
    if (было !== ЭКРАН) откудаПришли = было;
    /* На index.html профиль открывает нижняя вкладка — мимо дверей game.js,
       и его общая память возврата (экранОткудаПришли) остаётся старой.
       Дверь запомнить есть только там (js/game.js, рядом с
       «открытьПоверхТекущего») — зовём её здесь же, ДО показа своего
       экрана, чтобы «Назад» и стрелка Telegram (назадИзПрофиля через
       «вернутьсяОткудаПришли») вернули ровно туда, где были. На трёх
       других страницах двери нет — работает прежняя своя память. */
    const о = окно();
    if (о && typeof о.запомнитьМестоВозврата === 'function') о.запомнитьМестоВозврата();
    убедитьсяЧтоЭкранЕсть();
    заполнитьНижниеВкладки();
    показатьЭкран(ЭКРАН);
    попытатьсяПривязатьСтрелку(назадИзПрофиля);
    освежитьИмяИФото();
    освежитьСерию();
    обновитьДанные();
  }

  /* В браузере открываем дверь наружу сразу; в node (проверка чистых
     функций) страницы нет вовсе, и строить нечего. */
  if (typeof document !== 'undefined' && typeof window !== 'undefined') {
    window.ЭкранПрофиля = { открыть: открыть };
  }

  /* Наружу для проверки — только то, что решает, ЧТО показывать:
     ни одна из этих функций страницу не трогает, поэтому их можно
     прогнать в node без браузера. */
  if (typeof module !== 'undefined' && module.exports) {
    module.exports = {
      ЭКРАН: ЭКРАН,
      инициалы: инициалы,
      словаОСерииВПрофиле: словаОСерииВПрофиле,
      словаОБеде: словаОБеде,
      текстМеста: текстМеста,
      строкиОчков: строкиОчков,
      суммаОчков: суммаОчков
    };
  }

})();
