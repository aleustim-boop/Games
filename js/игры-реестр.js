  /** Копия списка: снаружи нельзя испортить реестр живой страницы. */
  function все() {
    return ИГРЫ.map(function (и) {
      const копия = Object.assign({}, и);
      копия.способОчков = и.способОчков.slice();
      if (и.бот) копия.бот = Object.assign({}, и.бот, { уровни: Object.assign({}, и.бот.уровни) });
      if (и.счёт) {
        // потолок/заСекунду/неБыстрее — число ИЛИ объект {режим: число}, копируем как есть или клоном
        const клонПоля = function (значение) {
          return (значение && typeof значение === 'object') ? Object.assign({}, значение) : значение;
        };
        копия.счёт = Object.assign({}, и.счёт, {
          режимы: и.счёт.режимы.map(function (р) { return Object.assign({}, р); }),
          потолок: клонПоля(и.счёт.потолок),
          заСекунду: клонПоля(и.счёт.заСекунду),
          неБыстрее: клонПоля(и.счёт.неБыстрее)
        });
      }
      return копия;
    });
  }

