'use strict';

/* =====================================================================
   ШАХМАТЫ — ЗВУК. Файлов со звуками в проекте нет: короткие сигналы
   собираются прямо в браузере (Web Audio API) — тем же приёмом, что
   у дурака и шашек. Код нарочно повторён, а не вынесен в общий файл:
   так решено ещё на второй игре — «дурака не режем, дублируем немного
   и спим спокойно».

   ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА: ТЕ ЖЕ ВЫСОТЫ, ЧТО У СОСЕДЕЙ.
   Три игры сборника не должны звучать по-разному, когда происходит одно
   и то же. Человек, перешедший из шашек в шахматы, не должен заново
   учиться слышать «так нельзя». Поэтому частоты здесь не выбраны заново,
   а взяты из js/шашки-звук.js слово в слово:

     ход       262 Гц    — короткий тихий щелчок, фигура встала на поле
     отказ     150 Гц    — ниже и короче хода: «так нельзя»
     взятие    196 + 147 — то же, что бой в шашках: ниже и вдвое длиннее
     победа    523-659-784 (до-ми-соль вверх)
     поражение 300-160 (две ноты вниз)
     ничья     392 дважды (ни вверх, ни вниз)

   ЧТО ЗДЕСЬ СВОЁ — ШАХ. У шашек такого события нет вовсе. Шах — не ход,
   а предупреждение, и звучит он парой нот сверху вниз (587 → 494):
   выше хода, чтобы не спутать с обычной перестановкой, короче победы,
   чтобы не показаться концом партии.

   ДВА ПРАВИЛА, КОТОРЫЕ ЗДЕСЬ НЕЛЬЗЯ НАРУШАТЬ.

   1. Звук не начинается до первого касания. Браузеры на телефоне не дают
      звука без действия человека: движок, созданный до тапа, остаётся
      «приостановленным» навсегда. Поэтому движок создаётся лениво —
      при первом сигнале, — а первый сигнал бывает внутри нажатия.
      Ход робота звучит уже через готовый движок.

   2. Единственная дорога к динамику — «сигнал()», и только он смотрит
      на выключатель. Поэтому кнопка «Звук» глушит всё разом, и никакой
      новый звук не сможет её обойти.

   Наружу файл отдаёт window.ШахматыЗвук: ход(), взятие(), отказ(), шах(),
   победа(), поражение(), ничья(), включён(), переключить().
   ===================================================================== */

(function () {
  /* Ключ выбора — латиницей. Правило всего проекта: имена записей
     собираются из латинских букв (подробно — раздел «Имена ключей»
     в js/telegram.js). У соседей ключи звука кириллические, и это
     наследство: их заводили до правила. Новую запись заводим по правилу,
     чтобы не добавлять работы задаче про разнобой ключей. */
  var КЛЮЧ_ЗВУКА = 'sound_chess';
  var ГРОМКОСТЬ = 0.07;         // тихо: в шахматы часто играют в наушниках в транспорте
  /* Итог партии звучит с задержкой: последний ход только что щёлкнул,
     и фанфары поверх него слились бы в кашу. */
  var ПАУЗА_ПЕРЕД_ИТОГОМ = 0.15;
  /* Сколько ждать между двумя отказами. Человек, который тычет в занятое
     поле подряд, иначе получает очередь щелчков — и это уже не подсказка,
     а дребезг. Столько же держит вибрация в js/telegram.js. */
  var ПАУЗА_МЕЖДУ_ОТКАЗАМИ = 200;

  var звуковойДвижок = null;
  var последнийОтказ = 0;

  function прочитатьНастройку() {
    try {
      return window.localStorage.getItem(КЛЮЧ_ЗВУКА);
    } catch (ошибка) {
      return null;   // память запрещена — считаем, что звук включён
    }
  }

  function записатьНастройку(значение) {
    try {
      window.localStorage.setItem(КЛЮЧ_ЗВУКА, значение);
    } catch (ошибка) { /* запрещённая память — не повод ломать игру */ }
  }

  var звукВключён = прочитатьНастройку() !== 'выключен';

  /** Звуковой движок браузера. Создаём при первом звуке: до нажатия браузер его не даёт. */
  function получитьЗвуковойДвижок() {
    if (звуковойДвижок) return звуковойДвижок;
    try {
      var Движок = window.AudioContext || window.webkitAudioContext;
      if (!Движок) return null;
      звуковойДвижок = new Движок();
    } catch (ошибка) {
      звуковойДвижок = null;
    }
    return звуковойДвижок;
  }

  /**
   * Один короткий сигнал: частота в герцах, длительность и задержка в секундах.
   * Нарастание и затухание нужны обязательно — без них слышен щелчок на краях.
   */
  function сигнал(частота, длительность, задержка) {
    if (!звукВключён) return;
    var движок = получитьЗвуковойДвижок();
    if (!движок) return;
    try {
      if (движок.state === 'suspended') движок.resume();
      var начало = движок.currentTime + (задержка || 0);
      var генератор = движок.createOscillator();
      var громкость = движок.createGain();
      генератор.type = 'triangle';        // мягче синуса и без резкости квадрата
      генератор.frequency.setValueAtTime(частота, начало);
      громкость.gain.setValueAtTime(0.0001, начало);
      громкость.gain.exponentialRampToValueAtTime(ГРОМКОСТЬ, начало + 0.012);
      громкость.gain.exponentialRampToValueAtTime(0.0001, начало + длительность);
      генератор.connect(громкость);
      громкость.connect(движок.destination);
      генератор.start(начало);
      генератор.stop(начало + длительность + 0.02);
    } catch (ошибка) {
      /* звук — не то, ради чего стоит ронять игру */
    }
  }

  function звукХода()      { сигнал(262, 0.05); }
  function звукВзятия()    { сигнал(196, 0.10); сигнал(147, 0.16, 0.08); }
  /* Шах — предупреждение, а не ход: пара нот сверху вниз. */
  function звукШаха()      { сигнал(587, 0.07); сигнал(494, 0.12, 0.07); }

  /** «Так нельзя». Часто подряд — поэтому с паузой, иначе выйдет очередь щелчков. */
  function звукОтказа() {
    var сейчас = Date.now();
    if (сейчас - последнийОтказ < ПАУЗА_МЕЖДУ_ОТКАЗАМИ) return;
    последнийОтказ = сейчас;
    сигнал(150, 0.05);
  }

  function звукПобеды() {
    сигнал(523, 0.12, ПАУЗА_ПЕРЕД_ИТОГОМ);
    сигнал(659, 0.12, ПАУЗА_ПЕРЕД_ИТОГОМ + 0.13);
    сигнал(784, 0.26, ПАУЗА_ПЕРЕД_ИТОГОМ + 0.26);
  }
  function звукПоражения() {
    сигнал(300, 0.16, ПАУЗА_ПЕРЕД_ИТОГОМ);
    сигнал(160, 0.30, ПАУЗА_ПЕРЕД_ИТОГОМ + 0.16);
  }
  function звукНичьей() {
    сигнал(392, 0.10, ПАУЗА_ПЕРЕД_ИТОГОМ);
    сигнал(392, 0.14, ПАУЗА_ПЕРЕД_ИТОГОМ + 0.15);
  }

  function переключитьЗвук() {
    звукВключён = !звукВключён;
    записатьНастройку(звукВключён ? 'включен' : 'выключен');
    показатьСостояниеЗвука();
    if (звукВключён) звукХода();   // сразу слышно, что включилось
  }

  /* Подпись короткая — «Звук», как у шашек: ряд кнопок под доской на узком
     телефоне и так полон, а включён звук или нет, показывает кружок слева
     (правило для #кнопка-звук в общем style.css). */
  function показатьСостояниеЗвука() {
    if (!кнопка) return;
    кнопка.textContent = 'Звук';
    кнопка.classList.toggle('кнопка--выключено', !звукВключён);
    кнопка.setAttribute('aria-label', звукВключён ? 'Звук включён' : 'Звук выключен');
  }

  /**
   * Кнопка «Звук». В разметке шахмат её нет вовсе — в отличие от шашек,
   * где она стоит в html. Поэтому берём готовую, если она появится, а нет —
   * ставим сами в тот же ряд, где «Поворот доски» и «Буквы и цифры»,
   * перед кнопкой «Назад»: выключатель без кнопки бесполезен, а звук
   * без выключателя нельзя выпускать к людям.
   */
  function найтиИлиСоздатьКнопку() {
    var готовая = document.getElementById('кнопка-звук');
    if (готовая) return готовая;

    var сосед = document.getElementById('кнопка-метки') || document.getElementById('кнопка-назад');
    if (!сосед || !сосед.parentNode) return null;

    var своя = document.createElement('button');
    своя.id = 'кнопка-звук';
    своя.type = 'button';
    своя.className = 'кнопка кнопка--мелкая';
    своя.textContent = 'Звук';
    // Рядом с «Буквами и цифрами», до «Назад»: выход со страницы остаётся последним
    сосед.parentNode.insertBefore(своя, сосед.nextSibling);
    return своя;
  }

  var кнопка = найтиИлиСоздатьКнопку();
  if (кнопка) кнопка.addEventListener('click', переключитьЗвук);
  показатьСостояниеЗвука();

  window.ШахматыЗвук = {
    ход: звукХода,
    взятие: звукВзятия,
    отказ: звукОтказа,
    шах: звукШаха,
    победа: звукПобеды,
    поражение: звукПоражения,
    ничья: звукНичьей,
    включён: function () { return звукВключён; },
    переключить: переключитьЗвук
  };
})();
