/* =====================================================================
   ЗНАКИ ВНИМАНИЯ В ШАШКАХ — смайлики, фразы и броски предметов.

   Зачем отдельный файл. Списки нужны сразу двоим: экрану шашек (нарисовать
   панель) и серверу (проверить присланный номер и решить, подаст ли голос
   бот). Ровно так же устроено у дурака, только там списки лежат внутри
   js/game.js вместе с правилами карт. Тащить карточный файл на страницу
   шашек ради двух списков было бы странно, а класть знаки в шашечные
   правила — тоже: там правила игры, а знак внимания к правилам не
   относится. Поэтому свой маленький файл, который читают обе стороны.

   ВНИМАНИЕ, ДВЕ КОПИИ. Список бросков здесь ТОТ ЖЕ, что у дурака
   (см. БРОСКИ и ПОРЯДОК_БРОСКОВ_В_ПАНЕЛИ в js/game.js): предметы игре
   не принадлежат и должны выглядеть одинаково за любым столом. Правишь
   один список — правь и второй. Это данные, а не логика; разойтись они
   могут только если кто-то поменяет одно место и забудет другое.

   ФРАЗЫ — свои, шашечные. Дураковские тут бессмысленны: «бито»,
   «подкидываю», «беру» за доской не значат ничего.

   ЧЕГО В ФРАЗАХ НЕТ НАРОЧНО — дразнилок. Для шуток есть смайлики и
   броски, а фраза висит на экране дольше и читается злее, чем задумана
   тем, кто её нажал.

   НУМЕРАЦИЯ СКВОЗНАЯ, с единицы: сначала смайлики, потом фразы, потом
   броски. Так же, как у дурака, — и не ради красоты: комната, защита от
   частых нажатий и выбор цели броска написаны один раз на обе игры и
   работают с номерами, а не со списками.
   ===================================================================== */

/* Смайлики — те же, что у дурака (js/game.js, ЭМОЦИИ). */
const ЭМОЦИИ = ['👍', '😀', '😮', '😢', '😎', '🤔', '🔥', '👏'];

/* Фразы — свои, про шашки. Десять штук: больше человек не прочитает
   на телефоне, меньше — не хватит на партию. */
const ФРАЗЫ = [
  'Хороший ход!',
  'Красивая комбинация',
  'Бью!',
  'У меня дамка!',
  'Не ожидал…',
  'Ваш ход',
  'Не спешите, думайте',
  'Может, ничья?',
  'Хорошая партия!',
  'Мне повезло'
];

/* Броски — те же пятнадцать предметов, что у дурака (js/game.js, БРОСКИ):
   рисунки владельца img/бросок/<ключ>.webp вместо значков телефона,
   которые у всех выглядят по-разному.

   ПО СЕТИ ЕДЕТ НОМЕР, поэтому порядок этого списка — договор со старыми
   страницами и сервером, а не вид:
     — первые семь предметов стоят на местах прежних значков (💩, 🍅, 🥚,
       👞, ❤️, 🌹, 🍰): у шашек это номера 19–25, и старая страница
       с новой понимают такой бросок одинаково;
     — место звезды (⭐, номер 26) занял «Огонь», как у дурака: дыру
       оставлять нельзя — сервер проверяет только, что номер в списке;
     — новые предметы — в конец, номера 27–33. Старая страница их
       не знает и молчит (её «знакПоНомеру» пустой).
   Номера у шашек свои (у дурака броски с 23-го): фраз здесь десять,
   а не одиннадцать. Проверяет их сервер по этому же файлу
   (server/игры/шашки.js), поэтому договор один — этот список.

   «злой» — по нему бот выбирает, чем отвечать: на злое злым, на доброе
   добрым, и получается перепалка, а не случайный мусор. */
const БРОСКИ = [
  { ключ: 'какашка', имя: 'Какашка', злой: true },       // было 💩
  { ключ: 'помидор', имя: 'Помидор', злой: true },       // было 🍅
  { ключ: 'яйцо', имя: 'Яйцо', злой: true },             // было 🥚
  { ключ: 'тапок', имя: 'Тапок', злой: true },           // было 👞
  { ключ: 'сердце', имя: 'Сердце', злой: false },        // было ❤️
  { ключ: 'роза', имя: 'Роза', злой: false },            // было 🌹
  { ключ: 'торт', имя: 'Торт', злой: false },            // было 🍰
  { ключ: 'огонь', имя: 'Огонь', злой: false },          // место ⭐
  { ключ: 'шарик-с-водой', имя: 'Шарик с водой', злой: true },
  { ключ: 'банан', имя: 'Банан', злой: true },
  { ключ: 'рыба', имя: 'Рыба', злой: true },
  { ключ: 'снежок', имя: 'Снежок', злой: true },
  { ключ: 'перчатка', имя: 'Перчатка', злой: true },
  { ключ: 'бомба', имя: 'Бомба', злой: true },
  { ключ: 'пиво', имя: 'Пиво', злой: false }
];

/* В каком порядке предметы стоят в панели «Кинуть» — как у дурака, как
   их прислал владелец. Номера по сети от этого порядка не зависят. */
const ПОРЯДОК_БРОСКОВ_В_ПАНЕЛИ = [
  'какашка', 'помидор', 'яйцо', 'тапок', 'шарик-с-водой', 'торт', 'банан', 'рыба',
  'роза', 'сердце', 'снежок', 'перчатка', 'бомба', 'огонь', 'пиво'
];

/* Где лежат рисунки предметов. Имя файла — ключ предмета. Адрес — тоже
   данные, поэтому здесь; сам рисунок на экран ставит js/шашки-экран.js. */
const ПАПКА_БРОСКОВ = 'img/бросок/';

/** Сколько всего знаков — сквозная нумерация от 1 до этого числа. */
function сколькоЗнаков() {
  return ЭМОЦИИ.length + ФРАЗЫ.length + БРОСКИ.length;
}

/** Номер, с которого начинаются броски. */
function первыйНомерБроска() {
  return ЭМОЦИИ.length + ФРАЗЫ.length + 1;
}

/** Это вообще знак внимания? */
function этоЗнак(номер) {
  return Number.isInteger(номер) && номер >= 1 && номер <= сколькоЗнаков();
}

/** Это бросок — знак, которому нужен адресат? */
function этоБросок(номер) {
  return этоЗнак(номер) && номер >= первыйНомерБроска();
}

/** Предмет броска по номеру знака — запись из БРОСКИ или null. */
function предметБроска(номер) {
  return этоБросок(номер) ? БРОСКИ[номер - первыйНомерБроска()] : null;
}

/**
 * Что это за знак словами: смайлик, фраза или название предмета
 * («Помидор»). Рисунок предмета ставит экран. Чужой номер — пусто.
 */
function знакПоНомеру(номер) {
  if (!этоЗнак(номер)) return '';
  if (номер <= ЭМОЦИИ.length) return ЭМОЦИИ[номер - 1];
  if (номер <= ЭМОЦИИ.length + ФРАЗЫ.length) return ФРАЗЫ[номер - ЭМОЦИИ.length - 1];
  return предметБроска(номер).имя;
}

/** Злой ли это бросок. Не бросок — всегда нет. */
function бросокЗлой(номер) {
  const предмет = предметБроска(номер);
  return Boolean(предмет && предмет.злой);
}

/** Номер броска по ключу предмета («помидор»): −1, если такого нет. */
function номерБроска(ключ) {
  for (let i = 0; i < БРОСКИ.length; i++) {
    if (БРОСКИ[i].ключ === ключ) return первыйНомерБроска() + i;
  }
  return -1;
}

/**
 * Номера бросков в порядке панели. Предмет, которого нет в порядке
 * (допишут в БРОСКИ и забудут сюда), встаёт в конец, а не пропадает.
 */
function номераБросковВПорядкеПанели() {
  const номера = [];
  for (const ключ of ПОРЯДОК_БРОСКОВ_В_ПАНЕЛИ) {
    const номер = номерБроска(ключ);
    if (номер !== -1) номера.push(номер);
  }
  for (let номер = первыйНомерБроска(); номер <= сколькоЗнаков(); номер++) {
    if (номера.indexOf(номер) === -1) номера.push(номер);
  }
  return номера;
}

/** Где лежит рисунок предмета этого номера. Не бросок — пусто. */
function адресКартинкиПредмета(номер) {
  const предмет = предметБроска(номер);
  return предмет ? ПАПКА_БРОСКОВ + предмет.ключ + '.webp' : '';
}

/* Как часто бот подаёт голос сам. Числа те же, что у дурака, и по той же
   причине: бот, который говорит на каждом ходу, — это не собеседник,
   а трещотка. Кидает он ещё реже: бросок без повода — уже приставание. */
const ШАНС_ЗНАКА_БОТА = 0.06;
const ШАНС_БРОСКА_БОТА = 0.01;

/* Что бот может сказать сам: короткие и безобидные. Номера считаем от
   списков, чтобы правка списка не разъехалась с этим набором. */
function номераЗнаковБота() {
  return [
    1,                       // 👍
    2,                       // 😀
    6,                       // 🤔
    ЭМОЦИИ.length + 1,       // Хороший ход!
    ЭМОЦИИ.length + 6,       // Ваш ход
    ЭМОЦИИ.length + 9        // Хорошая партия!
  ];
}

/** Все номера бросков одной породы: злых или добрых. */
function номераБросков(злые) {
  const номера = [];
  for (let номер = первыйНомерБроска(); номер <= сколькоЗнаков(); номер++) {
    if (бросокЗлой(номер) === злые) номера.push(номер);
  }
  return номера;
}

function случайныйИз(список) {
  return список.length ? список[Math.floor(Math.random() * список.length)] : null;
}

/**
 * Подаст ли бот голос на своём ходу — номер знака или null.
 * Живёт здесь, а не в отрисовке, по той же причине, что у дурака:
 * за сетевым столом боты ходят на сервере, и решать за них должно то же
 * самое место, что и в игре без сети. Иначе сетевые боты молчали бы,
 * а местные разговаривали.
 */
function знакБота() {
  if (Math.random() >= ШАНС_ЗНАКА_БОТА) return null;
  return случайныйИз(номераЗнаковБота());
}

/**
 * Кинет ли бот чем-нибудь в человека — { номер, цель } или null.
 * Цель называет тот, кто зовёт: здесь мы знаем только, хочет ли бот
 * бросить и чем именно.
 */
function бросокБота() {
  if (Math.random() >= ШАНС_БРОСКА_БОТА) return null;
  const все = номераБросков(true).concat(номераБросков(false));
  const номер = случайныйИз(все);
  return номер ? { номер: номер } : null;
}

/* Как часто бот отвечает на смайлик или фразу — примерно каждый третий
   раз. Отвечать на каждый — это уже не собеседник, а эхо. */
const ШАНС_ОТВЕТА_НА_ЗНАК = 0.35;

/**
 * Чем бот ответит на знак человека — номер или null (промолчал).
 *
 * Одна дверь на все случаи: на бросок отвечает броском той же породы
 * (злым на злое, добрым на доброе), на смайлик или фразу — иногда своим
 * знаком. Пауза перед ответом — дело экрана, здесь только выбор.
 */
function ответНаЗнак(номер) {
  if (этоБросок(номер)) return ответНаБросок(номер);
  if (!этоЗнак(номер)) return null;
  if (Math.random() >= ШАНС_ОТВЕТА_НА_ЗНАК) return null;
  return случайныйИз(номераЗнаковБота());
}

/** Чем бот отвечает на бросок в него: злым на злое, добрым на доброе. */
function ответНаБросок(номер) {
  if (!этоБросок(номер)) return null;
  return случайныйИз(номераБросков(бросокЗлой(номер)));
}

const Знаки = {
  ЭМОЦИИ: ЭМОЦИИ,
  ФРАЗЫ: ФРАЗЫ,
  БРОСКИ: БРОСКИ,
  ПОРЯДОК_БРОСКОВ_В_ПАНЕЛИ: ПОРЯДОК_БРОСКОВ_В_ПАНЕЛИ,
  сколькоЗнаков: сколькоЗнаков,
  первыйНомерБроска: первыйНомерБроска,
  этоЗнак: этоЗнак,
  этоБросок: этоБросок,
  знакПоНомеру: знакПоНомеру,
  предметБроска: предметБроска,
  номерБроска: номерБроска,
  номераБросковВПорядкеПанели: номераБросковВПорядкеПанели,
  адресКартинкиПредмета: адресКартинкиПредмета,
  бросокЗлой: бросокЗлой,
  знакБота: знакБота,
  бросокБота: бросокБота,
  ответНаБросок: ответНаБросок,
  ответНаЗнак: ответНаЗнак
};

