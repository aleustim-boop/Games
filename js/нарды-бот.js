/* =====================================================================
   НАРДЫ — БОТ. Три уровня, обе версии.

   Про экран здесь не знают ничего: ни document, ни window, ни цветов.
   Файл читают и браузер, и Node — так же, как правила.

   ---------------------------------------------------------------------
   ПОЧЕМУ ЗДЕСЬ НЕТ ДЕРЕВА ПЕРЕБОРА, КАК В ШАХМАТАХ

   В шахматах сильный ход находят глубоким перебором: позиция полностью
   определена, и на десять полуходов вперёд считать осмысленно. В нардах
   так нельзя. После моего хода соперник бросает кубики, и веток
   становится 21 на каждый ход. Уже на третьем полуходе это сотни тысяч
   позиций, и все они — про случай, а не про мастерство.

   Поэтому бот устроен иначе: он перебирает СВОИ ходы целиком и
   оценивает получившуюся позицию, а «сложный» вдобавок смотрит, что
   соперник сможет сделать в ответ на каждый из 21 броска.

   ---------------------------------------------------------------------
   ГЛАВНОЕ: ХОДЫ БОТ НЕ ПРИДУМЫВАЕТ

   Все ходы бот берёт у правил — «Правила.возможныеХоды». Своего
   представления о том, как ходят в нардах, у него нет ни одной строчки.
   Незаконный ход поэтому не «маловероятен», а физически невозможен:
   его неоткуда взять.

   По той же причине разведка ответа соперника (уровень «сложный») тоже
   идёт через правила: мы бросаем сопернику кубики и спрашиваем у правил
   его ходы. Никаких своих подсчётов «на сколько бьёт шестёрка» — такой
   подсчёт был бы второй копией правил, а они у нас не раздваиваются.

   ---------------------------------------------------------------------
   ТРИ УРОВНЯ

     лёгкий  — близорукий гонщик. Считает только гонку: у кого меньше
               осталось шагов. Про бой, бар и заборы не знает вовсе,
               поэтому бросает шашки под удар и не строит стен.
               Случайный ход был бы не «слабым», а никаким — играть с
               таким обидно; этот же ошибается понятно, по-человечески.
     обычный — полная оценка позиции: гонка, бой, бар, дом, стены.
               Смотрит на один свой ход вперёд.
     сложный — то же, плюс разведка: для лучших своих ходов проверяет
               все 21 броска соперника и смотрит, много ли тот сможет
               разыграть и не побьёт ли нас.

   ---------------------------------------------------------------------
   ОЦЕНКА РАЗНАЯ ДЛЯ ВЕРСИЙ, И ЭТО НЕ МЕЛОЧЬ

   В длинных нардах боя нет вовсе. Значит, всё, что про одинокие шашки,
   бар и риск быть побитым, там не просто лишнее — оно вредное: бот
   боялся бы того, чего не бывает, и играл бы хуже. Поэтому веса и
   слагаемые у версий свои.
   ===================================================================== */

/* Правила берём одним и тем же файлом в обоих мирах. */
const Правила = (typeof require !== 'undefined' && typeof module !== 'undefined' && module.exports)
  ? require('./нарды-правила.js')
  : window.НардыПравила;

const УРОВНИ = ['лёгкий', 'обычный', 'сложный'];

/* Потолок раздумья. Больше — и на телефоне видна пауза; столько же
   держат бот шашек и бот шахмат. */
const ПОТОЛОК_МС = 300;

/* Сколько своих ходов разбираем. На дубле их иногда за три сотни, и
   разобрать все — это полсекунды только на раскладку. Берём самые
   осмысленные: список ходов правила отдают в разумном порядке, а разница
   между сотым и трёхсотым вариантом дубля почти всегда никакая. */
const КАНДИДАТОВ_МАКСИМУМ = 80;

/* Сколько лучших ходов «сложный» проверяет разведкой. Каждый стоит
   21 бросок соперника, поэтому их немного. */
const ГЛУБОКИХ_КАНДИДАТОВ = 16;

/* Все 21 сочетание кубиков с их весом: разные числа выпадают вдвое
   чаще дубля (5-3 бывает как 5-3 и как 3-5, а 4-4 — только одним
   способом). Сумма весов — 36. */
const БРОСКИ = (function () {
  const список = [];
  for (let а = 1; а <= 6; а++) {
    for (let б = а; б <= 6; б++) список.push({ кубики: [а, б], вес: а === б ? 1 : 2 });
  }
  return список;
})();

/* =====================================================================
   ЧАСТЬ 1. ЧЕРТЫ ПОЗИЦИИ

   Всё, что бот умеет замечать на доске. Считается через двери правил,
   поэтому здесь нет ни одного собственного суждения о том, кто куда
   ходит.
   ===================================================================== */

function соперникЦвета(цвет) { return цвет === Правила.БЕЛЫЕ ? Правила.ЧЁРНЫЕ : Правила.БЕЛЫЕ; }

/**
 * Черты одного цвета:
 *   пипс      — сколько шагов осталось всем шашкам вместе (меньше — лучше)
 *   вынос     — сколько уже снято с доски
 *   бар       — сколько сидит на баре
 *   ценаБлотов — во сколько шагов обойдётся, если каждую одинокую шашку
 *                собьют (и только те, до которых сопернику вообще есть чем
 *                дотянуться)
 *   домаЗакрыто — сколько пунктов своего дома занято двумя и больше
 *   стена     — во сколько ценится самая длинная сплошная стена
 */
function черты(партия, цвет) {
  const вид = Правила.видИгры(партия);
  const чужой = соперникЦвета(цвет);
  const мойБар = Правила.наБаре(партия, цвет).length;

  /* СКОЛЬКО ШАШЕК ЗАКРЫВАЮТ ПУНКТ — и это не мелочь, а разница между
     двумя играми. В коротких нардах пункт держат ДВЕ шашки: одна стоит
     под боем и не мешает сопернику вовсе. В длинных бить нельзя, и
     ОДНОЙ шашки довольно, чтобы пункт был закрыт наглухо.

     Сперва я посчитал обе версии по двойкам — и бот в длинных нардах
     перестал видеть и свой дом, и свои стены, потому что там их обычно
     строят одиночками. На проверке он еле обыгрывал случайного игрока;
     это и вывело на ошибку. */
  const порогЗакрытия = вид === Правила.ДЛИННЫЕ ? 1 : 2;

  let пипс = 25 * мойБар;
  let ценаБлотов = 0;

  /* Раскладываем доску в «остатки шагов» обоих цветов: в них считать
     удобнее всего, а сами числа даёт та же дверь правил. */
  const моиПоОстатку = new Array(25).fill(0);
  const чужиеПоОстатку = new Array(25).fill(0);
  const блоты = [];

  for (let п = 1; п <= 24; п++) {
    const место = Правила.пункт(партия, п);
    if (!место.сколько) continue;
    if (место.цвет === цвет) {
      const осталось = Правила.шаговОсталось(партия, цвет, п);
      пипс += место.сколько * осталось;
      моиПоОстатку[осталось] = место.сколько;
      if (место.сколько === 1) блоты.push({ пункт: п, осталось: осталось });
    } else {
      чужиеПоОстатку[Правила.шаговОсталось(партия, чужой, п)] = место.сколько;
    }
  }

  /* Одинокая шашка опасна только там, где сопернику есть чем до неё
     дойти, то есть если хоть одна его шашка ещё не прошла этот пункт.
     Цена удара — сколько шагов мы потеряем: битую отбрасывает в самое
     начало. Поэтому одинокая шашка у своего дома дороже, чем далеко от него. */
  const чужойБар = Правила.наБаре(партия, чужой).length;
  for (const блот of блоты) {
    const местоПоЧужому = Правила.шаговОсталось(партия, чужой, блот.пункт);
    let достанет = чужойБар > 0;
    if (!достанет) {
      for (let о = местоПоЧужому + 1; о <= 24; о++) if (чужиеПоОстатку[о] > 0) { достанет = true; break; }
    }
    if (достанет) ценаБлотов += 25 - блот.осталось;
  }

  let домаЗакрыто = 0;
  for (const п of Правила.дом(партия, цвет)) {
    const место = Правила.пункт(партия, п);
    if (место.сколько >= порогЗакрытия && место.цвет === цвет) домаЗакрыто++;
  }

  return {
    пипс: пипс,
    вынос: Правила.вынесенные(партия, цвет).length,
    бар: мойБар,
    ценаБлотов: ценаБлотов,
    домаЗакрыто: домаЗакрыто,
    стена: ценаСтены(моиПоОстатку, чужиеПоОстатку, вид, порогЗакрытия)
  };
}

/**
 * Самая длинная сплошная стена и её польза. Стена ценна не сама по
 * себе, а тем, сколько чужих шашек осталось позади неё: стена, которую
 * все уже прошли, не стоит ничего.
 */
function ценаСтены(моиПоОстатку, чужиеПоОстатку, вид, порогЗакрытия) {
  let лучшая = 0;
  let длина = 0;
  for (let о = 24; о >= 1; о--) {
    if (моиПоОстатку[о] >= порогЗакрытия) {
      длина++;
      if (длина >= 2) {
        /* Верхний конец стены в моих остатках — о + длина - 1. Тот же
           пункт в остатках соперника: доска одна, а головы стоят
           наискосок ровно через полдоски (в коротких — навстречу). */
        const верх = о + длина - 1;
        const поЧужому = вид === Правила.ДЛИННЫЕ ? ((верх + 11) % 24) + 1 : 25 - верх;
        let позади = 0;
        for (let ч = поЧужому + 1; ч <= 24; ч++) позади += чужиеПоОстатку[ч];
        const цена = длина * длина * 0.1 * позади;
        if (цена > лучшая) лучшая = цена;
      }
    } else {
      длина = 0;
    }
  }
  return лучшая;
}

/* =====================================================================
   ЧАСТЬ 2. ОЦЕНКА ПОЗИЦИИ

   Считается всегда «моё минус чужое»: так оценка сама собой остаётся
   честной и не зависит от того, за кого мы играем.
   ===================================================================== */

const ВЕСА = {};
ВЕСА[Правила.КОРОТКИЕ] = {
  пипс: 1.0, вынос: 3.0, бар: 12.0, блот: 0.55, дом: 2.5, стена: 1.2
};
ВЕСА[Правила.ДЛИННЫЕ] = {
  пипс: 1.0, вынос: 3.0, бар: 0, блот: 0, дом: 2.5, стена: 2.0
};

/** Насколько позиция хороша для этого цвета. Больше — лучше. */
function оценка(партия, цвет) {
  const вид = Правила.видИгры(партия);
  const в = ВЕСА[вид];
  const чужой = соперникЦвета(цвет);

  /* Партия кончилась — считать нечего, важен только исход и его цена. */
  if (Правила.партияЗавершена(партия)) {
    const итог = Правила.итог(партия);
    const знак = итог.победитель === цвет ? 1 : -1;
    return знак * 1000 * итог.цена;
  }

  const моё = черты(партия, цвет);
  const чужое = черты(партия, чужой);

  let счёт = в.пипс * (чужое.пипс - моё.пипс);
  счёт += в.вынос * (моё.вынос - чужое.вынос);
  счёт += в.дом * (моё.домаЗакрыто - чужое.домаЗакрыто);
  счёт += в.стена * (моё.стена - чужое.стена);

  /* Бой, бар и одинокие шашки бывают только в коротких нардах.
     В длинных эти веса нулевые, и слагаемые исчезают сами. */
  счёт += в.бар * (чужое.бар - моё.бар);
  счёт += в.блот * (чужое.ценаБлотов - моё.ценаБлотов);

  return счёт;
}

/* ---------------------------------------------------------------------
   ЧЕМ СЛАБ «ЛЁГКИЙ». Он смотрит на доску теми же глазами, что и
   «обычный», но невнимательно: к оценке каждого хода прибавляется
   заметная случайная поправка, и потому он часто выбирает не лучшее.
   Играет он при этом осмысленно — просто ошибается, как ошибается
   человек, который правила знает, а привычки ещё нет.

   ПОЧЕМУ НЕ ПО-ДРУГОМУ. Сперва «лёгкий» был близоруким гонщиком: считал
   только, у кого меньше осталось шагов. Проверка показала две беды.
   В длинных нардах он оказался слабее случайного игрока: там все ходы
   продвигают на одну и ту же сумму кубиков, и гонка ничего не
   подсказывает вовсе. А в коротких партии перестали кончаться — за
   тысячу ходов: бой отбрасывает соперника на два десятка шагов, вынос
   даёт вчетверо меньше, и такой игрок бесконечно бьёт вместо того,
   чтобы доигрывать. Обе беды нашла лестница силы, а не рассуждение. */
const ШУМ_ЛЁГКОГО = 1.2;

/* =====================================================================
   ЧАСТЬ 3. РАЗВЕДКА ОТВЕТА — только уровень «сложный»

   Что будет, если соперник бросит кубики? Проверяем все 21 сочетание и
   смотрим на две вещи:

     сколько очков он сумеет разыграть — если мы перегородили ему дорогу,
       часть кубиков у него пропадёт, и это ровно то, ради чего в нардах
       строят стены;
     не побьёт ли он нас и во сколько шагов это обойдётся.

   Оба ответа берутся из ходов, которые выдали правила: у каждого
   перемещения там уже написан кубик и имя побитой шашки. Ходы при этом
   НЕ применяются — считать по списку дешевле в разы, и именно поэтому
   разведка укладывается в отведённое время.
   ===================================================================== */

function разведкаОтвета(послеХода, мойЦвет, срок) {
  let суммаОчков = 0;
  let суммаБоя = 0;
  let весаПосчитанные = 0;

  for (const бросок of БРОСКИ) {
    /* Сторож времени стоит ВНУТРИ обхода бросков, а не только снаружи.
       Сперва он был только снаружи — и одна разведка тяжёлой позиции
       успевала перебрать потолок на полсотни миллисекунд: проверка это
       поймала. Если время вышло, отвечаем по тем броскам, что успели
       посмотреть: неполная разведка лучше, чем задержка на экране. */
    if (Date.now() > срок && весаПосчитанные > 0) break;
    весаПосчитанные += бросок.вес;
    const проба = Правила.копияПартии(послеХода);
    Правила.бросить(проба, бросок.кубики);
    const ходы = Правила.возможныеХоды(проба);

    let лучшиеОчки = 0;
    let худшийБой = 0;
    for (const ход of ходы) {
      let очки = 0;
      let бой = 0;
      for (const шаг of ход.шаги) {
        очки += шаг.кубик;
        if (шаг.побита) {
          /* Сколько шагов мы потеряем: битую отбрасывает в самое начало,
             к двадцати пяти. «Куда» — это пункт, где она стояла. */
          const потеря = 25 - Правила.шаговОсталось(проба, мойЦвет, шаг.куда);
          if (потеря > бой) бой = потеря;
        }
      }
      if (очки > лучшиеОчки) лучшиеОчки = очки;
      if (бой > худшийБой) худшийБой = бой;
    }
    суммаОчков += бросок.вес * лучшиеОчки;
    суммаБоя += бросок.вес * худшийБой;
  }

  /* Делим на посчитанный вес, а не на 36: иначе прерванная разведка
     занижала бы опасность и бот считал бы позицию безопаснее, чем она есть. */
  return { очки: суммаОчков / весаПосчитанные, бой: суммаБоя / весаПосчитанные };
}

/* Насколько сильно разведка влияет на выбор. Веса свои у каждой версии,
   и это не придирка: в коротких соперник почти всегда разыгрывает оба
   кубика, и «сколько он сможет» там мало что говорит — зато важно, не
   побьёт ли он нас. В длинных ровно наоборот: бить нечем, и вся польза
   разведки в том, чтобы перегородить сопернику дорогу.

   Эти веса поправляют оценку, а не заменяют её: «сложный» — тот же бот,
   только осмотрительнее. */
const ВЕСА_РАЗВЕДКИ = {};
ВЕСА_РАЗВЕДКИ[Правила.КОРОТКИЕ] = { очки: 0.15, бой: 1.0 };
ВЕСА_РАЗВЕДКИ[Правила.ДЛИННЫЕ] = { очки: 0.60, бой: 0 };

/* =====================================================================
   ЧАСТЬ 4. ВЫБОР ХОДА
   ===================================================================== */

/** Ход целиком применяется к копии — оригинал бот не трогает никогда. */
function послеХода(партия, ход) {
  const копия = Правила.копияПартии(партия);
  return Правила.сделатьХод(копия, ход) ? копия : null;
}

/**
 * Выбрать ход. Возвращает то же, что «возможныеХоды»: ход со списком
 * перемещений по порядку — экран покажет их по одному. Ходить нечем —
 * возвращает null, и это не ошибка: в нардах бросок бывает пустым.
 *
 *   партия  — позиция, кубики уже брошены
 *   уровень — 'лёгкий' | 'обычный' | 'сложный'
 */
function выбратьХод(партия, уровень, потолокМс) {
  if (Правила.партияЗавершена(партия)) return null;
  const ходы = Правила.возможныеХоды(партия);
  if (!ходы.length) return null;
  if (ходы.length === 1) return ходы[0];

  const цвет = Правила.чейХод(партия);
  /* Работаем не до самого потолка, а до трёх пятых от него.

     Запас нужен потому, что сторож времени срабатывает МЕЖДУ делами, а
     начатое дело доделывается целиком: один разбор хода на широком дубле
     сам по себе занимает десятки миллисекунд. Сперва запас был в одну
     пятую — и на ста пятидесяти тысячах ходов один раз вышло 318 мс при
     потолке 300. Один выброс на сто пятьдесят тысяч — всё равно нарушенное
     обещание, поэтому запас увеличен. */
  const срок = Date.now() + (потолокМс || ПОТОЛОК_МС) * 0.6;

  /* Разбираем не больше сотни с небольшим вариантов: на дубле их
     бывает втрое больше, а лишние — почти всегда перестановки того же
     самого. */
  const разбираем = ходы.length > КАНДИДАТОВ_МАКСИМУМ ? ходы.slice(0, КАНДИДАТОВ_МАКСИМУМ) : ходы;

  const оценённые = [];
  for (const ход of разбираем) {
    /* Сторож времени нужен и здесь: на дубле раскладка сотни вариантов
       сама по себе не бесплатна. Разобрали хоть что-то — уже есть из
       чего выбирать. */
    if (оценённые.length > 0 && Date.now() > срок) break;
    const позиция = послеХода(партия, ход);
    if (!позиция) continue;                 // правила не приняли — пропускаем молча
    оценённые.push({ ход: ход, позиция: позиция, счёт: оценка(позиция, цвет) });
  }
  if (!оценённые.length) return ходы[0];

  /* «Лёгкий» смотрит теми же глазами, но невнимательно: поправка тем
     заметнее, чем сильнее ходы отличаются друг от друга. Поэтому в
     очевидных позициях он всё же ходит верно, а в спорных — как повезёт. */
  if (уровень === 'лёгкий') {
    let наибольший = -Infinity;
    let наименьший = Infinity;
    for (const в of оценённые) {
      if (в.счёт > наибольший) наибольший = в.счёт;
      if (в.счёт < наименьший) наименьший = в.счёт;
    }
    const разброс = наибольший - наименьший;
    for (const в of оценённые) в.счёт += (Math.random() - 0.5) * ШУМ_ЛЁГКОГО * разброс;
  }

  оценённые.sort(function (а, б) { return б.счёт - а.счёт; });

  if (уровень === 'сложный') {
    const вид = Правила.видИгры(партия);
    const весаРазведки = ВЕСА_РАЗВЕДКИ[вид];
    const глубокие = оценённые.slice(0, ГЛУБОКИХ_КАНДИДАТОВ);

    /* СРАВНИВАЕМ ТОЛЬКО РАЗВЕДАННОЕ МЕЖДУ СОБОЙ.

       Это не мелочь, а самая дорогая ошибка во всей работе. Сперва
       сторож времени просто обрывал цикл, и в общем списке оставались
       вперемешку ходы разведанные (с вычтенной опасностью) и
       неразведанные (без неё). Сравнивать их нельзя: у неразведанного
       штрафа нет, поэтому он всегда выглядит лучше — и «сложный» под
       нехваткой времени выбирал именно то, чего НЕ посмотрел. Он
       становился не осторожнее, а глупее обычного.

       Поймалось это на противоречии в измерениях: в отдельных матчах
       «сложный» выигрывал 54–57%, а в полной лестнице — 45%. Разница
       была в загрузке машины: когда рядом считалось что-то ещё, сторож
       срабатывал раньше и порча вылезала. Числа спорили друг с другом,
       и это оказалось важнее любого из них. */
    const разведанные = [];
    for (const вариант of глубокие) {
      /* Хотя бы один ход разведываем всегда — иначе сравнивать нечего. */
      if (разведанные.length > 0 && Date.now() > срок) break;
      if (Правила.партияЗавершена(вариант.позиция)) {   // выиграли — разведывать нечего
        разведанные.push(вариант);
        continue;
      }
      const ответ = разведкаОтвета(вариант.позиция, цвет, срок);

      /* СНАЧАЛА СНИМАЕМ ПРИБЛИЗИТЕЛЬНЫЙ СТРАХ, ПОТОМ СТАВИМ ИЗМЕРЕННЫЙ.
         В обычной оценке за свои одинокие шашки уже начислен штраф —
         это грубая прикидка опасности. Разведка меряет ту же самую
         опасность точно. Если оставить оба, бот боится боя дважды и
         играет слишком робко, а робость в нардах проигрывает.

         Так и вышло: на двухстах партиях «сложный» набрал против
         «обычного» 56%, а на следующих двухстах — 45%, то есть не был
         сильнее вовсе. Разницу нашла лестница, а не рассуждение. */
      вариант.счёт += ВЕСА[вид].блот * черты(вариант.позиция, цвет).ценаБлотов;
      вариант.счёт -= весаРазведки.очки * ответ.очки;
      вариант.счёт -= весаРазведки.бой * ответ.бой;
      разведанные.push(вариант);
    }
    разведанные.sort(function (а, б) { return б.счёт - а.счёт; });
    return изРавных(разведанные);
  }

  return изРавных(оценённые);
}

/**
 * Из нескольких одинаково хороших ходов берём случайный. Иначе бот в
 * одинаковых позициях ходит одинаково, и играть с ним скучно уже к
 * третьей партии.
 */
function изРавных(оценённые) {
  const лучший = оценённые[0].счёт;
  const равные = оценённые.filter(function (в) { return в.счёт > лучший - 0.001; });
  return равные[Math.floor(Math.random() * равные.length)].ход;
}

