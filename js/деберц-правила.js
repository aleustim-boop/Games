'use strict';

/* Деберц на 2–4 игроков и 2 на 2, до 301/501/1001, без обмена семёрки.
 * Источник: https://debertz.igrafan.ru/help/debertz.html
 * Объявления автоматические; длинный ряд даёт старший полтинник,
 * остаток из трёх/четырёх карт — ещё одну непересекающуюся комбинацию.
 * Победитель определяется после сдачи; деберц даёт немедленную победу.
 * Деберц: https://onlineigry.com/show/rules/deberc — козырные 8–Т.
 * Чистый модуль: пригоден и для браузера, и для будущего сервера.
 */
(function () {
  const масти = ['♠', '♥', '♦', '♣'];
  const ряд = ['7', '8', '9', '10', 'В', 'Д', 'К', 'Т'];
  const обычные = ['7', '8', '9', 'В', 'Д', 'К', '10', 'Т'];
  const козырные = ['7', '8', 'Д', 'К', '10', 'Т', '9', 'В'];
  function сила(карта, козырь) {
    return (карта.масть === козырь ? козырные : обычные).indexOf(карта.имя);
  }
  function очки(карта, козырь) {
    if (карта.масть === козырь && карта.имя === 'В') return 20;
    if (карта.масть === козырь && карта.имя === '9') return 14;
    return { Т: 11, '10': 10, К: 4, Д: 3, В: 2 }[карта.имя] || 0;
  }
  function бьёт(карта, первую, козырь) {
    return карта.масть === первую.масть ? сила(карта, козырь) > сила(первую, козырь)
      : карта.масть === козырь;
  }
  function колода(случайно) {
    const карты = масти.flatMap(масть => ряд.map(имя => ({ id: масть + имя, масть, имя })));
    for (let i = карты.length - 1; i > 0; i--) {
      const j = Math.floor(случайно() * (i + 1));
      [карты[i], карты[j]] = [карты[j], карты[i]];
    }
    return карты;
  }
  const цели = [301, 501, 1001];
  const режимы = { '2': 'Вдвоём', '3': 'Втроём', '4': 'Вчетвером', '2x2': '2 на 2' };
  const мест = и => и.руки?.length || и.мест || 2;
  const следующий = (и, игрок) => (игрок + 1) % мест(и);
  const команда = (и, игрок) => и.парами ? игрок % 2 : игрок;
  const суммы = (и, значения) => значения.reduce((а, n, i) => { а[команда(и, i)] += n; return а; }, Array(и.парами ? 2 : мест(и)).fill(0));
  const показКомбинаций = и => и.фаза === 'взятка' && и.взятки.every(n => n === 0) && и.объявления.some(список => список.some(к => к.название === 'Терц' || к.название === 'Полтинник'));
  function победить(и, сторона) {
    и.победитель = сторона;
    и.победители = Array.from({ length: мест(и) }, (_, i) => i).filter(i => команда(и, i) === сторона);
    и.фаза = 'конец';
  }
  function создать(случайно = Math.random, цель = 301, сДеберцем = true, режим = '2', версияПравил = 5) {
    if (!цели.includes(цель)) throw Error('Выберите 301, 501 или 1001 очко');
    if (!Object.hasOwn(режимы, режим)) throw Error('Неизвестный режим');
    const n = режим === '2x2' ? 4 : Number(режим), парами = режим === '2x2';
    const жеребьёвка = версияПравил >= 4 ? колода(случайно) : null;
    const доТуза = жеребьёвка ? жеребьёвка.slice(0, жеребьёвка.findIndex(к => к.имя === 'Т') + 1) : null;
    const игра = { режим, мест: n, парами, цель, сДеберцем, версияПравил, жеребьёвка: доТуза,
      счёт: Array(парами ? 2 : n).fill(0), историяРаздач: [], висят: 0,
      сдающий: доТуза ? (доТуза.length - 1) % n : Math.floor(случайно() * n), номер: 0, победитель: null, победители: [] };
    раздать(игра, случайно);
    return игра;
  }
  function раздать(игра, случайно = Math.random) {
    if (игра.фаза && !['итог', 'пересдача'].includes(игра.фаза)) throw Error('Сдача ещё не закончена');
    if (игра.следующийСдающий != null) { игра.сдающий = игра.следующийСдающий; игра.следующийСдающий = null; }
    const карты = колода(случайно);
    const n = мест(игра), нули = () => Array(n).fill(0);
    Object.assign(игра, { руки: Array.from({ length: n }, () => карты.splice(0, 6)),
      открытая: карты.shift(), запас: карты, фреза: null, фаза: 'торговля', круг: 1, пасы: 0,
      ход: следующий(игра, игра.сдающий), козырь: null, заказчик: null, стол: [],
      взятки: нули(), очки: нули(), бонусы: нули(), белла: Array(n).fill(false),
      белаОбъявлена: Array(n).fill(false), белаСтатус: Array(n).fill(null), объявления: Array.from({ length: n }, () => []),
      номер: игра.номер + 1, итог: null, последняяВзятка: null, сыграно: [] });
    return игра;
  }
  function вариантыКозыря(игра) {
    if (игра.фаза !== 'торговля') return [];
    return игра.круг === 1 ? [игра.открытая.масть] : масти.filter(м => м !== игра.открытая.масть);
  }
  function обязанВыбрать(игра) {
    return игра.версияПравил >= 4 && игра.фаза === 'торговля' && игра.круг === 2 && игра.ход === игра.сдающий;
  }
  function комбинации(рука, козырь) {
    const найденные = [];
    for (const масть of масти) {
      let серия = [];
      function записать() {
        while (серия.length >= 3) {
          const длина = серия.length >= 4 ? 4 : 3;
          const верх = серия[серия.length - 1];
          найденные.push({ название: длина === 4 ? 'Полтинник' : 'Терц', очки: длина === 4 ? 50 : 20, верх, масть,
            вес: (длина === 4 ? 100 : 0) + верх * 2 + Number(масть === козырь) });
          серия = серия.slice(0, -длина);
        }
        серия = [];
      }
      ряд.forEach((имя, i) => {
        if (рука.some(к => к.масть === масть && к.имя === имя)) серия.push(i);
        else записать();
      });
      записать();
    }
    return найденные.sort((a, b) => b.вес - a.вес);
  }
  // Вариант: семь козырей от восьмёрки до туза — немедленная победа.
  function деберц(рука, козырь) {
    return ряд.slice(1).every(имя => рука.some(к => к.имя === имя && к.масть === козырь));
  }
  function торг(игра, игрок, масть) {
    if (игра.фаза !== 'торговля' || игра.ход !== игрок) throw Error('Сейчас не ваша очередь выбирать козырь');
    if (масть === null) {
      if (обязанВыбрать(игра)) throw Error('У сдающего обяз: выберите козырь');
      игра.пасы++;
      игра.ход = следующий(игра, игрок);
      if (игра.пасы === мест(игра)) { игра.круг = 2; игра.ход = следующий(игра, игра.сдающий); }
      if (игра.пасы === мест(игра) * 2) { игра.фаза = 'пересдача'; игра.сдающий = следующий(игра, игра.сдающий); }
      return;
    }
    if (!вариантыКозыря(игра).includes(масть)) throw Error('Эту масть сейчас выбрать нельзя');
    игра.козырь = масть;
    игра.заказчик = игрок;
    if (мест(игра) === 4) {
      // Открытая карта достаётся сдающему; остальные семь — в прикуп.
      игра.руки.forEach((рука, i) => рука.push(...игра.запас.splice(0, i === игра.сдающий ? 1 : 2)));
      игра.руки[игра.сдающий].push(игра.открытая);
    } else игра.руки.forEach(рука => рука.push(...игра.запас.splice(0, 3)));
    игра.фреза = игра.запас[игра.запас.length - 1] || null;
    игра.объявления = игра.руки.map(рука => комбинации(рука, масть));
    const веса = игра.объявления.map(к => к.length ? к[0].вес : -1);
    const порядок = Array.from({ length: мест(игра) }, (_, i) => (игра.сдающий + 1 + i) % мест(игра));
    const старший = порядок.reduce((а, i) => веса[i] > веса[а] ? i : а, порядок[0]);
    игра.бонусы = игра.объявления.map((список, i) => команда(игра, i) === команда(игра, старший)
      ? список.reduce((с, к) => с + к.очки, 0) : 0);
    игра.белла = игра.руки.map(рука => ['Д', 'К'].every(имя => рука.some(к => к.масть === масть && к.имя === имя)));
    игра.фаза = 'игра';
    игра.ход = следующий(игра, игра.сдающий);
    const победитель = игра.сДеберцем ? игра.руки.findIndex(рука => деберц(рука, масть)) : -1;
    if (победитель !== -1) {
      игра.объявления[победитель] = [{ название: 'Деберц', очки: 0, масть, верх: 7, вес: 1000 }];
      игра.бонусы.fill(0);
      победить(игра, команда(игра, победитель));
      игра.итог = { сырые: игра.счёт.map(() => 0), запись: игра.счёт.map(() => 0), описание: 'Деберц! Семь козырей от восьмёрки до туза — победа в партии' };
    }
  }
  function доступные(игра, игрок) {
    if (игра.фаза !== 'игра' || игра.ход !== игрок) return [];
    const рука = игра.руки[игрок];
    if (!игра.стол.length) return рука.slice();
    const первая = игра.стол[0].карта;
    const лидирует = старшаяКарта(игра);
    const партнёрБерёт = игра.парами && команда(игра, лидирует.игрок) === команда(игра, игрок);
    const вМасть = рука.filter(к => к.масть === первая.масть);
    if (вМасть.length) {
      if (первая.масть === игра.козырь && !партнёрБерёт) {
        const старше = вМасть.filter(к => бьёт(к, лидирует.карта, игра.козырь));
        if (старше.length) return старше;
      }
      return вМасть;
    }
    const козыри = рука.filter(к => к.масть === игра.козырь);
    if (козыри.length && лидирует.карта.масть === игра.козырь && !партнёрБерёт) {
      const старше = козыри.filter(к => бьёт(к, лидирует.карта, игра.козырь));
      if (старше.length) return старше;
    }
    return козыри.length ? козыри : рука.slice();
  }
  function старшаяКарта(игра) {
    return игра.стол.reduce((а, б) => !а || бьёт(б.карта, а.карта, игра.козырь) ? б : а, null);
  }
  function сыграть(игра, игрок, id) {
    const карта = доступные(игра, игрок).find(к => к.id === id);
    if (!карта) throw Error('Этой картой сейчас ходить нельзя');
    игра.руки[игрок].splice(игра.руки[игрок].findIndex(к => к.id === id), 1);
    if (игра.белла[игрок] && карта.масть === игра.козырь && ['Д', 'К'].includes(карта.имя)) {
      if ((игра.версияПравил || 1) < 5) игра.очки[игрок] += 20;
      else игра.белаСтатус[игрок] = 'ждёт';
      игра.белла[игрок] = false;
      (игра.белаОбъявлена ||= [false, false])[игрок] = true;
    }
    игра.стол.push({ игрок, карта });
    игра.сыграно.push(карта);
    игра.ход = следующий(игра, игрок);
    if (игра.стол.length === мест(игра)) игра.фаза = 'взятка';
  }
  function забрать(игра) {
    if (игра.фаза !== 'взятка') throw Error('Взятка ещё не разыграна');
    const победитель = старшаяКарта(игра).игрок;
    // Объявление относится именно к этой взятке: последующие победы
    // уже не могут принести очки за проигранную белу.
    игра.белаСтатус?.forEach((статус, игрок) => {
      if (статус !== 'ждёт') return;
      const взяли = команда(игра, игрок) === команда(игра, победитель);
      игра.белаСтатус[игрок] = взяли ? 'засчитана' : 'проиграна';
      if (взяли) игра.очки[игрок] += 20;
    });
    игра.очки[победитель] += игра.стол.reduce((с, к) => с + очки(к.карта, игра.козырь), 0);
    игра.взятки[победитель]++;
    игра.последняяВзятка = { победитель, карты: игра.стол.slice() };
    игра.стол = [];
    игра.ход = победитель;
    игра.фаза = 'игра';
    if (игра.руки.every(рука => !рука.length)) {
      игра.очки[победитель] += 10;
      завершить(игра);
    }
  }
  function завершить(игра) {
    const взятки = суммы(игра, игра.взятки);
    const сырые = суммы(игра, игра.очки.map((n, i) => n + (взятки[команда(игра, i)] ? игра.бонусы[i] : 0)));
    const заказ = команда(игра, игра.заказчик);
    const соперники = сырые.map((_, i) => i).filter(i => i !== заказ);
    const максимум = Math.max(...соперники.map(i => сырые[i]));
    const запись = сырые.slice();
    let описание = 'Козырь оправдан';
    if (сырые[заказ] < максимум) {
      // В игре каждый за себя очки заказчика поровну переходят остальным.
      // Остаток по одному очку раздаём по очереди после заказчика.
      const порядок = соперники.slice().sort((a, b) => (a - заказ + сырые.length) % сырые.length - (b - заказ + сырые.length) % сырые.length);
      const делим = запись[заказ] + игра.висят; игра.висят = 0;
      порядок.forEach((i, k) => { запись[i] += Math.floor(делим / порядок.length) + Number(k < делим % порядок.length); });
      запись[заказ] = 0; описание = 'Байт';
    } else if (сырые[заказ] === максимум) {
      игра.висят += запись[заказ]; запись[заказ] = 0; описание = 'Висячий байт';
    }
    const лидеры = сырые.map((n, i) => n === Math.max(...сырые) ? i : -1).filter(i => i >= 0);
    const сдающийСейчас = игра.сдающий;
    if (лидеры.length === 1) {
      const старший = лидеры[0];
      запись[старший] += игра.висят; игра.висят = 0;
      игра.сдающий = игра.парами ? следующий(игра, игра.сдающий) : старший;
    } else игра.сдающий = мест(игра) === 2 ? соперники[0] : следующий(игра, игра.сдающий);
    if (игра.версияПравил >= 4) { игра.следующийСдающий = игра.сдающий; игра.сдающий = сдающийСейчас; }
    игра.счёт = игра.счёт.map((n, i) => n + запись[i]);
    игра.итог = { сырые, запись, описание };
    (игра.историяРаздач ||= []).push({ номер: игра.номер, запись: запись.slice(), счёт: игра.счёт.slice() });
    игра.фаза = 'итог';
    const лучшие = игра.счёт.map((n, i) => n === Math.max(...игра.счёт) ? i : -1).filter(i => i >= 0);
    if (Math.max(...игра.счёт) >= (игра.цель || 301) && лучшие.length === 1) победить(игра, лучшие[0]);
  }
  function сдаться(игра, игрок) {
    if (игра.фаза === 'конец') throw Error('Партия уже завершена');
    игра.победители = Array.from({ length: мест(игра) }, (_, i) => i).filter(i => команда(игра, i) !== команда(игра, игрок));
    игра.победитель = команда(игра, игра.победители[0]); игра.фаза = 'конец'; игра.сдался = true;
    игра.итог = { описание: 'Игрок сдался', сырые: суммы(игра, игра.очки), запись: игра.счёт.map(() => 0) };
  }
  const правила = { масти, ряд, цели, режимы, мест, команда, суммы, показКомбинаций, старшаяКарта, сдаться, деберц, создать, раздать, вариантыКозыря, обязанВыбрать, торг, доступные, сыграть, забрать, очки, сила, бьёт, комбинации };
  if (typeof module !== 'undefined' && module.exports) module.exports = правила;
  if (typeof window !== 'undefined') window.ДеберцПравила = правила;
})();
