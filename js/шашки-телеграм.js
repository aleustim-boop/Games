'use strict';

/* =====================================================================
   ШАШКИ — СВЯЗЬ С TELEGRAM И КНОПКА «НАЗАД».

   Что здесь есть и чего здесь нет.

   ЧЕГО НЕТ. Здесь нет ни хранения рекордов, ни цветов темы, ни команды
   «раскрыть окно на весь экран». Всё это уже делает js/telegram.js —
   тот самый файл, которым живёт дурак, и на странице шашек он подключён
   первым. Второй раз то же самое писать нельзя: две обвязки, которые
   каждая по-своему здороваются с Telegram, однажды разойдутся, и
   разбираться в этом будет некому.

   ЧТО ЕСТЬ. Ровно две вещи, которых у дурака нет и быть не может:

   1) КНОПКА «НАЗАД». Из шашек должно быть куда выйти. Внутри Telegram
      берём его собственную стрелку «Назад» наверху окна — она привычна,
      её не надо искать, и она не отнимает у доски ни одной точки высоты.
      Тогда своя кнопка на странице прячется, чтобы не было двух «назад»
      подряд. Вне Telegram стрелки нет, и работает кнопка на странице.

      КУДА ВЕДЁТ «НАЗАД» — и почему именно туда. Витрины с выбором игры
      пока нет, она в очереди. Уводим на index.html — единственную
      другую страницу мини-приложения (сейчас там дурак). Выбор не
      временный: витрина по плану вырастет ровно на этом же месте,
      то есть в index.html, и адрес менять не придётся. Закрывать
      мини-приложение целиком (Telegram это умеет) — плохо: человек
      нажимает «назад», чтобы вернуться, а не чтобы выйти из игры.

   2) ПОДСТРАХОВКА. Если js/telegram.js почему-то не доехал (сеть
      оборвалась на середине), окно Telegram останется шторкой снизу
      и игрок увидит четверть доски. Тогда здороваемся сами — двумя
      строчками, без темы и без хранилища.

   Порядок подключения важен: файл слушает «назад» и сначала закрывает
   экран, открытый поверх доски (рекорды или «Как играть»), поэтому
   js/шашки-рекорды.js и js/шашки-как-играть.js должны быть подключены
   раньше. Если их нет — «назад» просто уводит со страницы.
   ===================================================================== */

(function () {
  /* Куда уходим по кнопке «Назад». Появится витрина с выбором игры —
     она будет по этому же адресу, и правку сюда вносить не придётся. */
  var СТРАНИЦА_ВЫХОДА = 'index.html';
  // Своя стрелка «Назад» в Telegram появилась начиная с этой версии
  var ВЕРСИЯ_СО_СТРЕЛКОЙ = '6.1';

  var кнопкаНазад = document.getElementById('кнопка-назад');
  var подключились = false;

  /** Объект Telegram WebApp, если страница открыта внутри Telegram. Иначе null. */
  function получитьWebApp() {
    try {
      if (window.Telegram && window.Telegram.WebApp) return window.Telegram.WebApp;
    } catch (ошибка) { /* нет так нет */ }
    return null;
  }

  /**
   * Что делает «назад».
   * Сначала закрываем то, что открыто поверх доски (экран рекордов), и только
   * если поверх ничего нет — уходим со страницы. Это привычное поведение:
   * одна стрелка отматывает по одному шагу, а не выбрасывает сразу наружу.
   */
  function назад() {
    // Открытых поверх доски экранов два — рекорды и «Как играть»; одновременно
    // они не бывают, поэтому закрываем тот, что открыт, и на этом всё.
    var экраны = [window.ШашкиРекорды, window.ШашкиКакИграть];
    for (var i = 0; i < экраны.length; i++) {
      try {
        if (экраны[i] && экраны[i].открыты()) {
          экраны[i].спрятать();
          return;
        }
      } catch (ошибка) { /* экрана нет — значит, и закрывать нечего */ }
    }
    window.location.href = СТРАНИЦА_ВЫХОДА;
  }

  /** Умеет ли этот Telegram показывать свою стрелку «Назад». */
  function стрелкаДоступна(приложение) {
    if (!приложение || !приложение.BackButton) return false;
    try {
      if (typeof приложение.isVersionAtLeast === 'function') {
        return приложение.isVersionAtLeast(ВЕРСИЯ_СО_СТРЕЛКОЙ);
      }
    } catch (ошибка) {
      return false;
    }
    return false;
  }

  /**
   * Подстраховка на случай, когда js/telegram.js не подключился.
   * Признак того, что он на месте, — появившийся window.loadScore: этот файл
   * создаёт его в самом конце, значит отработал целиком и с Telegram
   * уже поздоровался.
   */
  function поздороватьсяЕслиНекому(приложение) {
    if (typeof window.loadScore === 'function') return;
    console.warn('js/telegram.js не подключился: здороваемся с Telegram сами, ' +
                 'но рекордов и цветов темы в этой партии не будет.');
    try { if (typeof приложение.ready === 'function') приложение.ready(); } catch (ошибка) { /* не страшно */ }
    try { if (typeof приложение.expand === 'function') приложение.expand(); } catch (ошибка) { /* не страшно */ }
  }

  function подключиться() {
    if (подключились) return true;
    var приложение = получитьWebApp();
    if (!приложение) return false;
    подключились = true;

    поздороватьсяЕслиНекому(приложение);

    if (!стрелкаДоступна(приложение)) return true;
    try {
      приложение.BackButton.show();
      if (typeof приложение.onEvent === 'function') {
        приложение.onEvent('backButtonClicked', назад);
      }
      // Своя кнопка больше не нужна: стрелка Telegram делает то же самое
      if (кнопкаНазад) кнопкаНазад.classList.add('скрыт');
    } catch (ошибка) {
      // Стрелка не завелась — оставляем свою кнопку на странице видимой
      if (кнопкаНазад) кнопкаНазад.classList.remove('скрыт');
    }
    return true;
  }

  if (кнопкаНазад) кнопкаНазад.addEventListener('click', назад);

  /* Скрипт Telegram подключён с «defer» и к этой минуте мог ещё не отработать —
     тогда пробуем ещё раз, когда страница будет готова. Точно так же
     подстраховывается и js/telegram.js. */
  if (!подключиться()) {
    window.addEventListener('load', function () { подключиться(); });
  }

  window.ШашкиТелеграм = { назад: назад };
})();
