'use strict';
/* =====================================================================
   «ЗАХВАТ»: ПАМЯТЬ — всё, что игра хранит у игрока (этап А6).

   Что здесь: рекорды (ТЗ 8.9, 12), настройки, сохранение партии без сети
   (15.5), журнал одной партии (8.5). Только хранилище: ни document, ни Date,
   ни setTimeout, ни Math.random. Время и хранилища приходят доводом.

   Как хранится. Общая дверь js/telegram.js (saveScore/loadScore) умеет только
   «серию побед» и не знает наших строк (место, очки, раундов), а доступа к
   произвольному ключу наружу не даёт. Поэтому здесь — тот же приём, что у
   неё: сначала память телефона (localStorage, она всегда под рукой), и
   облако Telegram (CloudStorage) как второй дом. Облако молчит или отказало —
   игра этого не замечает. Ключи — только латиница (облако других не берёт).

   Что в облако не идёт: «zahvat-save» и «zahvat-journal». У облака потолок
   4096 байт на запись, а журнал партии его легко перерастёт; к тому же
   партия без сети живёт на одном телефоне.
   ===================================================================== */
(function () {
  const КЛЮЧИ = {
    рекорды: 'zahvat-records',
    выучено: 'zahvat-learned',
    звук: 'zahvat-sound',   // хозяин — js/захват-звук.js; здесь только чтение
    эффекты: 'zahvat-fx',
    значки: 'zahvat-icons',
    боты: 'zahvat-bots',
    сохранение: 'zahvat-save',
    журнал: 'zahvat-journal'
  };

  // Простые настройки: читаются и пишутся через «взять»/«положить».
  // Звук пишет сам js/захват-звук.js, вибрация идёт через общий Телеграм.отклик
  // (ключа zahvat-vibro нет): второй записи у них здесь не заводим.
  const НАСТРОЙКИ = ['выучено', 'эффекты', 'значки', 'боты'];

  // ТЗ 12: дома хранится до 50 строк (10 — только нижняя граница показа).
  const МАКС_РЕКОРДОВ = 50;
  // В облако кладём столько лучших строк, сколько влезает в 4096 байт (потолок записи), но не меньше 10.
  const ЛИМИТ_ОБЛАКА_БАЙТ = 4096;
  const МИН_В_ОБЛАКЕ = 10;
  const РЕЖИМЫ = ['боты', 'онлайн'];

  const ключГоден = /^[A-Za-z0-9_-]{1,128}$/;

  function целое(х) { return Number.isInteger(х) ? х : null; }

  /** Строка рекорда или null, если в ней не хватает честных полей. «когда» — число (мс), время телефона. */
  function привестиРекорд(с) {
    if (!с || typeof с !== 'object') return null;
    const когда = целое(с.когда), мест = целое(с.мест), место = целое(с.место);
    const очки = целое(с.очки), раундов = целое(с.раундов);
    if (когда === null || когда < 0 || мест === null || мест < 2 || мест > 6) return null;
    if (место === null || место < 1 || место > мест) return null;
    if (очки === null || раундов === null || раундов < 0) return null;
    if (РЕЖИМЫ.indexOf(с.режим) === -1) return null;
    return { когда: когда, режим: с.режим, мест: мест, место: место, очки: очки, раундов: раундов };
  }

  /** Порядок 8.9: место (лучше — выше), потом очки, потом дата (новее — выше). */
  function сравнитьРекорды(а, б) {
    if (а.место !== б.место) return а.место - б.место;
    if (а.очки !== б.очки) return б.очки - а.очки;
    return б.когда - а.когда;
  }

  /** Привести список к виду «честные строки, по порядку, не больше МАКС». Одинаковые строки схлопываются. */
  function собратьТаблицу(список) {
    const видели = {};
    const строки = [];
    for (const с of Array.isArray(список) ? список : []) {
      const р = привестиРекорд(с);
      if (!р) continue;
      const метка = JSON.stringify(р);
      if (видели[метка]) continue;
      видели[метка] = true;
      строки.push(р);
    }
    строки.sort(сравнитьРекорды);
    return строки.slice(0, МАКС_РЕКОРДОВ);
  }

  /** Длина текста в байтах UTF-8 (кириллица — по 2): облако считает потолок по ней. */
  function байтов(текст) {
    let н = 0;
    for (let i = 0; i < текст.length; i++) {
      const к = текст.charCodeAt(i);
      if (к < 0x80) н += 1; else if (к < 0x800) н += 2;
      else if (к >= 0xD800 && к < 0xDC00) { н += 4; i++; } else н += 3;
    }
    return н;
  }

  /** Лучшие строки, которые влезают в облачную запись (не меньше МИН_В_ОБЛАКЕ). Таблица уже по порядку. */
  function таблицаДляОблака(таблица) {
    let сколько = таблица.length;
    while (сколько > МИН_В_ОБЛАКЕ && байтов(JSON.stringify(таблица.slice(0, сколько))) > ЛИМИТ_ОБЛАКА_БАЙТ) сколько--;
    return таблица.slice(0, сколько);
  }

  function разобрать(текст) {
    if (typeof текст !== 'string' || !текст) return null;
    try { return JSON.parse(текст); } catch (_) { return null; }
  }

  /**
   * Открыть память.
   * среда: { память: как localStorage, облако: как CloudStorage или null }.
   */
  function открыть(среда) {
    const память = среда && среда.память;
    const облако = среда && среда.облако ? среда.облако : null;
    let досмотр = false;   // флажок живёт только в странице: после перезагрузки досмотра нет

    function читатьЛокально(ключ) {
      if (!память) return null;
      try { return память.getItem(ключ); } catch (_) { return null; }
    }
    function писатьЛокально(ключ, текст) {
      if (!память) return false;
      try { память.setItem(ключ, текст); return true; } catch (_) { return false; }
    }
    function стеретьЛокально(ключ) {
      if (!память) return false;
      try { память.removeItem(ключ); return true; } catch (_) { return false; }
    }
    // В облако: без ожидания ответа и без последствий при отказе.
    function писатьВОблако(ключ, текст) {
      if (!облако || !ключГоден.test(ключ)) return;
      try { облако.setItem(ключ, текст, function () {}); } catch (_) { /* облако — второй дом, не первый */ }
    }
    function записатьВезде(ключ, значение) {
      const текст = JSON.stringify(значение);
      const вПамяти = писатьЛокально(ключ, текст);
      писатьВОблако(ключ, текст);
      return вПамяти;
    }

    /* ---------- настройки ---------- */

    function ключНастройки(имя) {
      if (НАСТРОЙКИ.indexOf(имя) === -1) throw new Error('Нет такой настройки: ' + имя);
      return КЛЮЧИ[имя];
    }
    function взять(имя, поУмолчанию) {
      const текст = читатьЛокально(ключНастройки(имя));
      const значение = разобрать(текст);
      return значение === null ? поУмолчанию : значение;
    }
    function положить(имя, значение) {
      return записатьВезде(ключНастройки(имя), значение);
    }

    /** Звук: только чтение того, что записал js/захват-звук.js. Нет записи — поУмолчанию. */
    function прочитатьЗвук(поУмолчанию) {
      const значение = разобрать(читатьЛокально(КЛЮЧИ.звук));
      return значение === null ? поУмолчанию : значение;
    }

    /* ---------- рекорды ---------- */

    function рекорды() {
      return собратьТаблицу(разобрать(читатьЛокально(КЛЮЧИ.рекорды)));
    }
    /** Добавить строку партии. Одиннадцатая вытесняет худшую. Возвращает таблицу или null, если строка негодная. */
    function добавитьРекорд(строка) {
      const р = привестиРекорд(строка);
      if (!р) return null;
      const таблица = собратьТаблицу(рекорды().concat([р]));
      писатьЛокально(КЛЮЧИ.рекорды, JSON.stringify(таблица));
      отправитьРекордыВОблако();
      return таблица;
    }
    function сводка() {
      const т = рекорды();
      return { сыграно: т.length, побед: т.filter(function (р) { return р.место === 1; }).length,
        лучшийСчёт: т.reduce(function (м, р) { return Math.max(м, р.очки); }, 0) };
    }

    /* ---------- сохранение партии без сети (15.5) ---------- */

    /** Пока идёт «Досмотреть быстро», сохранение не пишется вовсе: иначе после перезагрузки появится второй «Продолжить партию». */
    function начатьДосмотр() { досмотр = true; }
    function закончитьДосмотр() { досмотр = false; }
    function идётДосмотр() { return досмотр; }

    /** Записать партию. «нет» — идёт досмотр, партия не объект или память отказала. */
    function записатьСохранение(партия) {
      if (досмотр) return false;
      if (!партия || typeof партия !== 'object' || Array.isArray(партия)) return false;
      return писатьЛокально(КЛЮЧИ.сохранение, JSON.stringify(партия));
    }
    function прочитатьСохранение() {
      const п = разобрать(читатьЛокально(КЛЮЧИ.сохранение));
      return п && typeof п === 'object' && !Array.isArray(п) ? п : null;
    }
    /** Очистка разрешена и при досмотре: ключ чистят в миг выбытия, до листа «Вы выбыли». */
    function очиститьСохранение() { return стеретьЛокально(КЛЮЧИ.сохранение); }

    /* ---------- журнал одной партии (8.5) ---------- */

    /** Новая партия затирает прежний журнал. стол — код стола или «боты». */
    function начатьЖурнал(стол, номерПартии) {
      const журнал = { стол: String(стол), партия: номерПартии, раунды: [] };
      писатьЛокально(КЛЮЧИ.журнал, JSON.stringify(журнал));
      return журнал;
    }
    function прочитатьЖурнал() {
      const ж = разобрать(читатьЛокально(КЛЮЧИ.журнал));
      return ж && typeof ж === 'object' && Array.isArray(ж.раунды) ? ж : null;
    }
    /** Дописать раунд. Тот же номер второй раз заменяет первый, а не двоит строки. Нет журнала — «нет». */
    function добавитьРаундЖурнала(номер, строки) {
      const ж = прочитатьЖурнал();
      if (!ж || !Number.isInteger(номер) || !Array.isArray(строки)) return false;
      const запись = { номер: номер, строки: строки.map(String) };
      const где = ж.раунды.findIndex(function (р) { return р.номер === номер; });
      if (где === -1) ж.раунды.push(запись); else ж.раунды[где] = запись;
      ж.раунды.sort(function (а, б) { return а.номер - б.номер; });
      return писатьЛокально(КЛЮЧИ.журнал, JSON.stringify(ж));
    }
    function очиститьЖурнал() { return стеретьЛокально(КЛЮЧИ.журнал); }

    /* ---------- подтянуть из облака ---------- */

    /**
     * Спросить облако и влить найденное: рекорды — сложить с местными (строка не
     * теряется ни там, ни там), настройки — взять, только если дома пусто.
     * готово(изменилось) вызовется, когда ответят все; облако молчит — не вызовется.
     */
    /**
     * Сложить таблицу облака с местной. Что нашлось у облака лишнего — берём домой,
     * чего не хватает облаку — досылаем. Вызывается ТОЛЬКО по ответу облака: отказ
     * и молчание — это «не знаем, что там», и затирать неизвестное своим нельзя.
     * Возвращает «да», если дома что-то изменилось.
     */
    function влитьРекордыОблака(текстОблака) {
      const местные = рекорды();
      const облачные = собратьТаблицу(разобрать(текстОблака));
      const вместе = собратьТаблицу(местные.concat(облачные));
      const домаИзменилось = JSON.stringify(вместе) !== JSON.stringify(местные);
      if (домаИзменилось) писатьЛокально(КЛЮЧИ.рекорды, JSON.stringify(вместе));
      const дляОблака = JSON.stringify(таблицаДляОблака(вместе));
      if (вместе.length && дляОблака !== JSON.stringify(облачные)) писатьВОблако(КЛЮЧИ.рекорды, дляОблака);
      return домаИзменилось;
    }
    /** После новой партии: дома пишем сразу, в облако — только сложив с тем, что там лежит. */
    function отправитьРекордыВОблако() {
      if (!облако) return;
      let один = false;
      const ответ = function (сбой, текст) {
        if (один) return;
        один = true;
        if (!сбой) влитьРекордыОблака(typeof текст === 'string' ? текст : '');
      };
      try { облако.getItem(КЛЮЧИ.рекорды, ответ); } catch (_) { /* облако — второй дом */ }
    }

    function подтянуть(готово) {
      if (!облако) { if (готово) готово(false); return; }
      const имена = ['рекорды'].concat(НАСТРОЙКИ);
      let ждём = имена.length, изменилось = false;
      const ответили = function () { ждём--; if (ждём === 0 && готово) готово(изменилось); };
      имена.forEach(function (имя) {
        const ключ = КЛЮЧИ[имя];
        let один = false;
        const ответ = function (сбой, текст) {
          if (один) return;
          один = true;
          if (!сбой && имя === 'рекорды') {
            if (влитьРекордыОблака(текст)) изменилось = true;
          } else if (!сбой && typeof текст === 'string' && текст && читатьЛокально(ключ) === null && разобрать(текст) !== null) {
            писатьЛокально(ключ, текст); изменилось = true;
          }
          ответили();
        };
        try { облако.getItem(ключ, ответ); } catch (_) { ответ('сбой'); }
      });
    }

    return {
      взять: взять, положить: положить, прочитатьЗвук: прочитатьЗвук,
      рекорды: рекорды, добавитьРекорд: добавитьРекорд, сводка: сводка,
      начатьДосмотр: начатьДосмотр, закончитьДосмотр: закончитьДосмотр, идётДосмотр: идётДосмотр,
      записатьСохранение: записатьСохранение, прочитатьСохранение: прочитатьСохранение, очиститьСохранение: очиститьСохранение,
      начатьЖурнал: начатьЖурнал, прочитатьЖурнал: прочитатьЖурнал,
      добавитьРаундЖурнала: добавитьРаундЖурнала, очиститьЖурнал: очиститьЖурнал,
      подтянуть: подтянуть
    };
  }

  /** Для страницы: берёт настоящие localStorage и облако Telegram (если есть и умеет). */
  function открытьДляСтраницы() {
    let память = null, облако = null;
    try { память = window.localStorage; } catch (_) { память = null; }
    try {
      const п = window.Telegram && window.Telegram.WebApp;
      if (п && п.CloudStorage && (typeof п.isVersionAtLeast !== 'function' || п.isVersionAtLeast('6.9'))) облако = п.CloudStorage;
    } catch (_) { облако = null; }
    return открыть({ память: память, облако: облако });
  }

  const модуль = {
    КЛЮЧИ: КЛЮЧИ, МАКС_РЕКОРДОВ: МАКС_РЕКОРДОВ, ЛИМИТ_ОБЛАКА_БАЙТ: ЛИМИТ_ОБЛАКА_БАЙТ,
    открыть: открыть, открытьДляСтраницы: открытьДляСтраницы
  };
  if (typeof module !== 'undefined' && module.exports) module.exports = модуль;
  if (typeof window !== 'undefined') window.ЗахватПамять = модуль;
})();
