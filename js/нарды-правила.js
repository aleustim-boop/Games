'use strict';

/* =====================================================================
   НАРДЫ — ПРАВИЛА ПАРТИИ. ДВЕ ВЕРСИИ В ОДНОМ ФАЙЛЕ.

   В этом файле нет ни одной строчки про внешний вид: он не знает про
   document, window, цвета и нажатия пальцем. Устроен так же, как правила
   шашек (js/шашки-правила.js) и шахмат (js/шахматы-правила.js): один и
   тот же файл читают браузер, Node-проверки и будущий сервер. Поэтому
   правила физически не могут разойтись между экраном, автопрогоном и
   сервером — расходиться нечему.

   ДВЕ ВЕРСИИ, И ОНИ ПРАВДА РАЗНЫЕ:

     «короткие»  — то, что в мире зовут backgammon (нарды-«шеш-беш»).
                   Расстановка по 2/5/3/5, шашку соперника БЬЮТ, битая
                   уезжает на бар и заходит заново, есть вынос с дома.

     «длинные»   — русские нарды, владелец назвал их «классическими».
                   Все пятнадцать шашек стоят на одном пункте (голова),
                   бить НЕЛЬЗЯ вовсе, зато есть запрет на забор из шести
                   и особое правило первого хода с головы.

   ---------------------------------------------------------------------
   ОТКУДА ВЗЯТЫ ПРАВИЛА

     [1] Правила backgammon Всемирной федерации (WBF Rules of Backgammon)
         и общепринятая сводка bkgm.com/rules.html — расстановка, бой и
         бар, вынос, обязательность обоих кубиков, гаммон и бэкгаммон.
     [2] en.wikipedia.org, «Backgammon», разделы Setup, Movement,
         Hitting and entering, Bearing off, Scoring.
     [3] ru.wikipedia.org, «Длинные нарды» — голова, запрет боя, забор
         из шести, марс.
     [4] Свод русских клубных правил длинных нард в том виде, в каком по
         ним играют в сетевых залах (Яндекс.Игры, «Нарды онлайн»):
         одна шашка с головы за ход и исключение на первом ходу при
         дублях 6-6, 4-4, 3-3.

   ---------------------------------------------------------------------
   ЧТО ИМЕННО Я ВЫБРАЛ ТАМ, ГДЕ ЛЮДИ ИГРАЮТ ПО-РАЗНОМУ

   Владелец играет с друзьями. Если у них принято иначе — пусть скажет,
   меняется каждое из этого одной-двумя строчками. Поэтому выписываю
   честно и по пунктам.

   1) ОБЯЗАН ЛИ ИГРОК ИСПОЛЬЗОВАТЬ ОБА КУБИКА. Да, в обеих версиях.
      Игрок обязан сыграть столько кубиков, сколько вообще возможно
      сыграть в этой позиции. Нельзя «сходить одним, потому что так
      выгоднее», если есть способ сходить двумя. Дубль — четыре хода,
      и правило то же: играем максимум из четырёх.
      Как это сделано в коде: при броске один раз считается «максимум
      кубиков», а дальше игроку показываются только те перемещения,
      после которых максимум ещё достижим. Смотри «глубина» и
      «возможныеШаги».

   2) ЧТО ДЕЛАТЬ, КОГДА ХОДИТЬ МОЖНО ТОЛЬКО ОДНИМ. Если сыграть удаётся
      ровно один кубик из двух, а по отдельности играются оба, — игрок
      ОБЯЗАН сыграть СТАРШИЙ. Если старший в одиночку не играется —
      играется младший. Если не играется ни один — ход пропадает целиком.
      Это правило [1], [2] и оно же принято в русских длинных нардах.
      СПОРНОЕ МЕСТО: часть компаний в длинных нардах разрешает выбирать
      любой из двух. У нас — старший, как в турнирных правилах.

   3) МАРС И КОКС.
      Короткие: обычная победа — 1 очко; марс (в мире gammon) — 2 очка,
      если проигравший не вынес ни одной шашки; кокс (в мире backgammon) —
      3 очка, если проигравший не вынес ни одной И у него осталась шашка
      на баре или в доме победителя.
      Длинные: обычная победа — 1 очко; марс — 2 очка, если проигравший
      не вынес ни одной шашки. КОКСА В ДЛИННЫХ НАРДАХ НЕТ: в них нет ни
      бара, ни осмысленного «дома победителя» (через дом соперника здесь
      проходит обычный маршрут). Это самый распространённый счёт [3].
      СПОРНОЕ МЕСТО: некоторые компании считают в длинных «домашний
      марс»/«кокс» по своим приметам. Если у владельца так — скажет,
      добавим третью цену в одном месте (смотри «записатьПобеду»).

   4) КУБ УДВОЕНИЯ (doubling cube) в коротких нардах НЕ СДЕЛАН. Это
      отдельная игра поверх игры, дома в неё играют редко, а в первой
      версии сборника её никто не ждал. Задел, не пропажа.

   5) ПЕРВЫЙ ХОД В ДЛИННЫХ. Взят самый ходовой вариант: с головы за ход
      снимается одна шашка, но на своём ПЕРВОМ ходу при дублях 6-6, 4-4
      и 3-3 — две. Правило не с потолка: при этих трёх дублях голова
      соперника стоит ровно так, что одной шашкой все четыре кубика не
      разыграть, и без поблажки часть хода пропадала бы всегда.
      СПОРНОЕ МЕСТО: встречается и «на первом ходу при любом дубле две
      шашки», и «две шашки, только если иначе не разыграть». У нас —
      именно 6-6, 4-4, 3-3.

   6) ЗАБОР ИЗ ШЕСТИ В ДЛИННЫХ. Нельзя занять шесть пунктов подряд, если
      впереди этого забора нет ни одной шашки соперника (вынесенные
      шашки считаются «впереди» — значит, заперты не все пятнадцать).
      Проверяется после КАЖДОГО перемещения, а не только в конце хода.
      Тонкость, которую обычно пропускают, разобрана прямо у функции
      «заборЗапрещён»: «шесть подряд» считается вдоль маршрута соперника,
      а не по номерам пунктов.

   7) КТО ХОДИТ ПЕРВЫМ. Правила сами кубики не бросают и жребий не мечут:
      кто начинает — говорят снаружи при создании партии, а числа на
      кубиках передаются в «бросить». Так сделано нарочно: в игре по сети
      случайность должна рождаться на сервере, а не у игрока в браузере.

   ---------------------------------------------------------------------
   ГЛАВНОЕ ДЛЯ ЭКРАНА: ЗДЕСЬ ЕСТЬ ИЗ ЧЕГО СДЕЛАТЬ ДВИЖЕНИЕ

   В картах анимацию однажды не смогли сделать потому, что узлы карт
   пересоздавались при каждой перерисовке: у новой карты нет прошлого
   места, и лететь ей неоткуда. Чтобы не повторять дорогой урок, правила
   отдают не только новое положение, но и что именно произошло:

     * у каждой шашки постоянное имя на всю партию: 'б1'..'б15' у белых,
       'ч1'..'ч15' у чёрных. Имя не меняется никогда — ни от боя, ни от
       выноса. Экран узнаёт шашку и ВЕЗЁТ её, а не создаёт заново;
     * пункт хранит не число, а стопку имён снизу вверх, поэтому у экрана
       всегда есть слой (какая шашка над какой);
     * ход возвращается СПИСКОМ ПЕРЕМЕЩЕНИЙ, по одному на кубик:
       { фишка, откуда, куда, кубик, побита, вынос }. Дубль — это четыре
       записи в списке, а не одно «стало так». Показ по шагам молча не
       работал три недели в шашках; здесь такой возможности нет.
   ===================================================================== */

/* =====================================================================
   ЧАСТЬ 1. ВИДЫ ИГРЫ, ЦВЕТА, ГЕОМЕТРИЯ ДОСКИ
   ===================================================================== */

const КОРОТКИЕ = 'короткие';
const ДЛИННЫЕ = 'длинные';
const БЕЛЫЕ = 'белые';
const ЧЁРНЫЕ = 'чёрные';

const ПУНКТОВ = 24;   // пунктов на доске
const ФИШЕК = 15;     // шашек у каждого
const БАР = 25;       // «остаток шагов» для шашки, сидящей на баре
const ВНЕ = 0;        // «остаток шагов» для вынесенной шашки

/** Кто соперник. */
function соперник(цвет) { return цвет === БЕЛЫЕ ? ЧЁРНЫЕ : БЕЛЫЕ; }

/** Цвет шашки прямо по её имени: 'б7' — белая, 'ч3' — чёрная. */
function цветФишки(имя) { return имя.charCodeAt(0) === 1073 ? БЕЛЫЕ : ЧЁРНЫЕ; }  // 1073 — это буква «б»

/* ---------------------------------------------------------------------
   ОСТАТОК ШАГОВ — то самое общее, ради чего обе версии живут в одном
   файле.

   Пункты доски снаружи называются числами 1..24 и у обоих игроков
   называются ОДИНАКОВО — иначе экран сошёл бы с ума. Но каждый игрок
   идёт по доске своей дорогой. Чтобы правила не раздваивались, всё
   считается в «остатке шагов»: сколько шагов этой шашке осталось до
   выхода с доски. 24 — только что начала, 1 — последний пункт перед
   выходом, 0 — уже вынесена, 25 — сидит на баре.

   В остатках обе версии совпадают ПОЛНОСТЬЮ: и ход, и вынос, и вход с
   бара пишутся одной формулой «остаток минус кубик». Различаются только
   две таблички перевода — они ниже, и это ровно шесть строк.

   Короткие: белые идут 24 → 1, чёрные 1 → 24 (навстречу друг другу).
   Длинные:  белые идут 24 → 1, чёрные 12 → 1 → 24 → 13, то есть оба
             катятся вокруг доски в одну сторону. Голова белых — пункт
             24, голова чёрных — пункт 12, они стоят наискосок.
   --------------------------------------------------------------------- */

/** Сколько шагов шашке этого цвета осталось, если она стоит на пункте. */
function остаток(вид, цвет, пункт) {
  if (цвет === БЕЛЫЕ) return пункт;
  if (вид === КОРОТКИЕ) return 25 - пункт;
  return ((пункт - 13 + ПУНКТОВ) % ПУНКТОВ) + 1;
}

/** Обратный перевод: на каком пункте стоит шашка с таким остатком. */
function пунктПоОстатку(вид, цвет, шагов) {
  if (цвет === БЕЛЫЕ) return шагов;
  if (вид === КОРОТКИЕ) return 25 - шагов;
  return ((шагов - 1 + 12) % ПУНКТОВ) + 1;
}

/* В длинных нардах пригодится ещё один перевод: мой остаток → остаток
   соперника на том же пункте. Считается он одинаково для обоих цветов
   (доска-то одна, а головы стоят наискосок ровно через полдоски). */
function остатокСоперника(мойОстаток) {
  return ((мойОстаток + 11) % ПУНКТОВ) + 1;
}

/** Дом игрока — шесть последних пунктов его дороги, откуда идёт вынос. */
function домЦвета(вид, цвет) {
  const список = [];
  for (let ш = 6; ш >= 1; ш--) список.push(пунктПоОстатку(вид, цвет, ш));
  return список;
}

/** Вся дорога игрока по порядку: от дальнего пункта к последнему. */
function маршрутЦвета(вид, цвет) {
  const список = [];
  for (let ш = ПУНКТОВ; ш >= 1; ш--) список.push(пунктПоОстатку(вид, цвет, ш));
  return список;
}

/** Голова — пункт, где в длинных нардах стоят все пятнадцать в начале. */
function головаЦвета(вид, цвет) { return пунктПоОстатку(вид, цвет, ПУНКТОВ); }

/* Начальные расстановки. Ключ — номер пункта, значение — сколько шашек.

   Короткие: у белых 2 на 24-м, 5 на 13-м, 3 на 8-м, 5 на 6-м; у чёрных
   всё зеркально (пункт p ↔ пункт 25−p). Итого по пятнадцать.
   Длинные: все пятнадцать на своей голове. */
const НАЧАЛО = {
  короткие: {
    белые: { 24: 2, 13: 5, 8: 3, 6: 5 },
    чёрные: { 1: 2, 12: 5, 17: 3, 19: 5 }
  },
  длинные: {
    белые: { 24: 15 },
    чёрные: { 12: 15 }
  }
};

/* =====================================================================
   ЧАСТЬ 2. ПАРТИЯ: КАК ОНА УСТРОЕНА, КАК СОЗДАЁТСЯ И ЧИТАЕТСЯ

   Пункт — это не число, а СТОПКА ИМЁН снизу вверх: ['б1','б2']. Так
   экран знает и сколько шашек, и какая над какой, и — главное — какая
   именно шашка поехала. Верхняя (последняя в списке) поднимается первой:
   так же, как рукой со стола.
   ===================================================================== */

/** Пустая доска: 25 стопок, нулевая не используется (пунктов 1..24). */
function пустыеПункты() {
  const пункты = new Array(ПУНКТОВ + 1);
  for (let п = 0; п <= ПУНКТОВ; п++) пункты[п] = [];
  return пункты;
}

/** Имена всех шашек цвета по порядку: б1..б15 либо ч1..ч15. */
function именаФишек(цвет) {
  const буква = цвет === БЕЛЫЕ ? 'б' : 'ч';
  const имена = [];
  for (let i = 1; i <= ФИШЕК; i++) имена.push(буква + i);
  return имена;
}

/**
 * Новая партия.
 *   настройки = { вид: 'короткие'|'длинные', первый: 'белые'|'чёрные' }
 * Кубики не бросаются — их бросают снаружи через «бросить».
 */
function создатьПартию(настройки) {
  const н = настройки || {};
  const вид = н.вид === ДЛИННЫЕ ? ДЛИННЫЕ : КОРОТКИЕ;
  const первый = н.первый === ЧЁРНЫЕ ? ЧЁРНЫЕ : БЕЛЫЕ;
  const партия = чистаяПартия(вид, первый);
  for (const цвет of [БЕЛЫЕ, ЧЁРНЫЕ]) {
    const имена = именаФишек(цвет);
    let следующая = 0;
    const расстановка = НАЧАЛО[вид][цвет];
    for (const ключ of Object.keys(расстановка)) {
      const пункт = Number(ключ);
      for (let i = 0; i < расстановка[ключ]; i++) партия.пункты[пункт].push(имена[следующая++]);
    }
  }
  return партия;
}

/** Заготовка партии без единой шашки — общая часть для всех создателей. */
function чистаяПартия(вид, ходит) {
  return {
    вид: вид,
    ходит: ходит,
    пункты: пустыеПункты(),
    бар: { белые: [], чёрные: [] },
    вне: { белые: [], чёрные: [] },
    /* что выпало на кубиках сейчас; null — ещё не бросали */
    бросок: null,
    /* значения, которые ещё не сыграны (дубль даёт четыре) */
    кубики: [],
    /* перемещения, уже сделанные в этом ходу — из них собирается ход */
    сыграно: [],
    /* сколько шашек уже снято с головы в этом ходу (длинные нарды) */
    сГоловы: 0,
    лимитГоловы: 1,
    /* сколько кубиков игрок ОБЯЗАН сыграть в этом ходу */
    максимумКубиков: 0,
    /* если играется только один кубик и обязателен старший — он здесь */
    обязательныйКубик: null,
    /* сколько ходов каждый уже сделал: нужно правилу первого хода */
    ходов: { белые: 0, чёрные: 0 },
    завершена: false,
    победитель: null,
    цена: 0,
    видПобеды: null,
    причина: ''
  };
}

/** Точная копия партии. Нужна боту и перебору: портить оригинал нельзя. */
function копияПартии(партия) {
  const к = чистаяПартия(партия.вид, партия.ходит);
  for (let п = 1; п <= ПУНКТОВ; п++) к.пункты[п] = партия.пункты[п].slice();
  к.бар.белые = партия.бар.белые.slice();
  к.бар.чёрные = партия.бар.чёрные.slice();
  к.вне.белые = партия.вне.белые.slice();
  к.вне.чёрные = партия.вне.чёрные.slice();
  к.бросок = партия.бросок ? партия.бросок.slice() : null;
  к.кубики = партия.кубики.slice();
  к.сыграно = партия.сыграно.slice();
  к.сГоловы = партия.сГоловы;
  к.лимитГоловы = партия.лимитГоловы;
  к.максимумКубиков = партия.максимумКубиков;
  к.обязательныйКубик = партия.обязательныйКубик;
  к.ходов = { белые: партия.ходов.белые, чёрные: партия.ходов.чёрные };
  к.завершена = партия.завершена;
  к.победитель = партия.победитель;
  к.цена = партия.цена;
  к.видПобеды = партия.видПобеды;
  к.причина = партия.причина;
  return к;
}

/**
 * Партия из расстановки, выписанной руками. Нужна проверкам и разбору
 * позиций:
 *
 *   партияИзРасстановки('короткие', {
 *     ходит: 'белые',
 *     белые: { 6: 14, бар: 1 },
 *     чёрные: { 20: 2, 1: 13 }
 *   })
 *
 * Ключи — номера пунктов, а также 'бар' и 'вне'. Если названо меньше
 * пятнадцати шашек, остальные считаются ВЫНЕСЕННЫМИ — так короче писать
 * позиции про вынос. Больше пятнадцати — ошибка, о ней скажут вслух.
 */
function партияИзРасстановки(вид, расстановка) {
  const настоящийВид = вид === ДЛИННЫЕ ? ДЛИННЫЕ : КОРОТКИЕ;
  const р = расстановка || {};
  const партия = чистаяПартия(настоящийВид, р.ходит === ЧЁРНЫЕ ? ЧЁРНЫЕ : БЕЛЫЕ);
  if (р.ходов) партия.ходов = { белые: р.ходов.белые || 0, чёрные: р.ходов.чёрные || 0 };
  for (const цвет of [БЕЛЫЕ, ЧЁРНЫЕ]) {
    const имена = именаФишек(цвет);
    let следующая = 0;
    const свои = р[цвет] || {};
    for (const ключ of Object.keys(свои)) {
      const сколько = свои[ключ];
      for (let i = 0; i < сколько; i++) {
        if (следующая >= ФИШЕК) throw new Error('У ' + цвет + ' в расстановке больше пятнадцати шашек');
        const имя = имена[следующая++];
        if (ключ === 'бар') партия.бар[цвет].push(имя);
        else if (ключ === 'вне') партия.вне[цвет].push(имя);
        else {
          const пункт = Number(ключ);
          if (!(пункт >= 1 && пункт <= ПУНКТОВ)) throw new Error('Нет такого пункта: ' + ключ);
          партия.пункты[пункт].push(имя);
        }
      }
    }
    /* Недосказанные шашки считаем вынесенными — иначе на доске окажется
       не пятнадцать, и любая проверка целостности справедливо покраснеет. */
    while (следующая < ФИШЕК) партия.вне[цвет].push(имена[следующая++]);
  }
  const беда = целостность(партия);
  if (беда) throw new Error('Расстановка неверна: ' + беда);
  return партия;
}

/* --- чтение партии: всё, что нужно экрану и боту, и ничего лишнего --- */

/** Что стоит на пункте: { цвет, сколько, фишки }. Пусто — цвет null. */
function пункт(партия, номер) {
  const стопка = партия.пункты[номер] || [];
  return {
    цвет: стопка.length ? цветФишки(стопка[0]) : null,
    сколько: стопка.length,
    фишки: стопка.slice()
  };
}

/** Имена шашек на баре (в длинных нардах бара нет, там всегда пусто). */
function наБаре(партия, цвет) { return партия.бар[цвет].slice(); }

/** Имена уже вынесенных шашек. */
function вынесенные(партия, цвет) { return партия.вне[цвет].slice(); }

/** Где сейчас конкретная шашка: { место, пункт, слой }. */
function гдеФишка(партия, имя) {
  const цвет = цветФишки(имя);
  for (let п = 1; п <= ПУНКТОВ; п++) {
    const слой = партия.пункты[п].indexOf(имя);
    if (слой !== -1) return { место: 'пункт', пункт: п, слой: слой };
  }
  let слой = партия.бар[цвет].indexOf(имя);
  if (слой !== -1) return { место: 'бар', пункт: null, слой: слой };
  слой = партия.вне[цвет].indexOf(имя);
  if (слой !== -1) return { место: 'вне', пункт: null, слой: слой };
  return null;
}

/**
 * Все тридцать шашек списком — это то, из чего экран рисует доску:
 * { имя, цвет, место: 'пункт'|'бар'|'вне', пункт, слой }.
 * Порядок всегда один и тот же, чтобы разметку можно было сравнивать.
 */
function всеФишки(партия) {
  const список = [];
  for (const цвет of [БЕЛЫЕ, ЧЁРНЫЕ]) {
    for (const имя of именаФишек(цвет)) {
      const место = гдеФишка(партия, имя);
      список.push({
        имя: имя, цвет: цвет,
        место: место.место, пункт: место.пункт, слой: место.слой
      });
    }
  }
  return список;
}

/** Чей сейчас ход. */
function чейХод(партия) { return партия.ходит; }

/** Какая версия игры идёт. */
function видИгры(партия) { return партия.вид; }

/** Что выпало сейчас: [3,5] или [4,4]. Ещё не бросали — null. */
function бросокПартии(партия) { return партия.бросок ? партия.бросок.slice() : null; }

/** Значения кубиков, которые ещё не сыграны в этом ходу. */
function кубикиПартии(партия) { return партия.кубики.slice(); }

/** Сколько кубиков игрок обязан сыграть в этом ходу. */
function максимумКубиков(партия) { return партия.максимумКубиков; }

/** Дом цвета — шесть пунктов, откуда идёт вынос. */
function дом(партия, цвет) { return домЦвета(партия.вид, цвет); }

/** Дорога цвета по пунктам, от дальнего к последнему. */
function маршрут(партия, цвет) { return маршрутЦвета(партия.вид, цвет); }

/** Голова цвета (в коротких нардах особого смысла не имеет). */
function голова(партия, цвет) { return головаЦвета(партия.вид, цвет); }

/** Сколько шагов осталось шашке этого цвета с такого пункта. */
function шаговОсталось(партия, цвет, номерПункта) {
  return остаток(партия.вид, цвет, номерПункта);
}

/**
 * Целостность позиции. Возвращает null, если всё в порядке, иначе —
 * текст беды человеческим языком. Это тот самый неизменный закон:
 * шашек всегда пятнадцать у каждого, где бы они ни были, и ни одна не
 * исчезает и не появляется.
 */
function целостность(партия) {
  const встречено = Object.create(null);
  const счёт = { белые: 0, чёрные: 0 };
  function учесть(имя, где) {
    if (встречено[имя]) return 'шашка ' + имя + ' встретилась дважды: ' + встречено[имя] + ' и ' + где;
    встречено[имя] = где;
    счёт[цветФишки(имя)]++;
    return null;
  }
  for (let п = 1; п <= ПУНКТОВ; п++) {
    const стопка = партия.пункты[п];
    for (const имя of стопка) {
      const беда = учесть(имя, 'пункт ' + п);
      if (беда) return беда;
      if (цветФишки(имя) !== цветФишки(стопка[0])) return 'на пункте ' + п + ' смешались белые и чёрные';
    }
  }
  for (const цвет of [БЕЛЫЕ, ЧЁРНЫЕ]) {
    for (const имя of партия.бар[цвет]) {
      const беда = учесть(имя, 'бар');
      if (беда) return беда;
      if (цветФишки(имя) !== цвет) return 'на баре ' + цвет + ' лежит чужая шашка ' + имя;
    }
    for (const имя of партия.вне[цвет]) {
      const беда = учесть(имя, 'вне доски');
      if (беда) return беда;
      if (цветФишки(имя) !== цвет) return 'среди вынесенных ' + цвет + ' есть чужая шашка ' + имя;
    }
  }
  for (const цвет of [БЕЛЫЕ, ЧЁРНЫЕ]) {
    if (счёт[цвет] !== ФИШЕК) return 'у ' + цвет + ' насчиталось ' + счёт[цвет] + ' шашек вместо пятнадцати';
  }
  if (партия.вид === ДЛИННЫЕ && (партия.бар.белые.length || партия.бар.чёрные.length)) {
    return 'в длинных нардах не бывает бара, а на нём кто-то стоит';
  }
  return null;
}

/**
 * Отпечаток позиции — короткая строка, по которой две позиции можно
 * сравнить целиком. Имён шашек в отпечатке нет нарочно: для правил
 * важно, СКОЛЬКО и чьих стоит на пункте, а не какая именно шашка.
 * Иначе перебор считал бы одно и то же по пятнадцать раз.
 */
function отпечатокПозиции(партия) {
  const части = [];
  for (let п = 1; п <= ПУНКТОВ; п++) {
    const стопка = партия.пункты[п];
    if (!стопка.length) { части.push('0'); continue; }
    части.push((цветФишки(стопка[0]) === БЕЛЫЕ ? '+' : '-') + стопка.length);
  }
  return части.join(',') + '|б' + партия.бар.белые.length + 'ч' + партия.бар.чёрные.length +
         '|в' + партия.вне.белые.length + 'ч' + партия.вне.чёрные.length +
         '|' + (партия.ходит === БЕЛЫЕ ? 'б' : 'ч');
}

/* =====================================================================
   ЧАСТЬ 3. БРОСОК КУБИКОВ

   Правила сами случайность не выдумывают: числа приходят снаружи. Если
   их не передали, кубики берутся встроенным Math.random — так удобно
   играть в одиночку в браузере, но сервер обязан передавать свои.
   ===================================================================== */

/** Один кубик: число от 1 до 6. */
function случайныйКубик() { return 1 + Math.floor(Math.random() * 6); }

/**
 * Бросок. Возвращает выпавшее ([3,5] или [4,4]) либо null, если бросать
 * сейчас нельзя. Здесь же считается, сколько кубиков игрок обязан
 * сыграть, и не обязан ли он играть именно старший.
 */
function бросить(партия, кубики) {
  if (партия.завершена) return null;
  if (партия.бросок) return null;              // сначала доиграй прошлый бросок
  const а = кубики && кубики.length === 2 ? Number(кубики[0]) : случайныйКубик();
  const б = кубики && кубики.length === 2 ? Number(кубики[1]) : случайныйКубик();
  if (!(а >= 1 && а <= 6 && б >= 1 && б <= 6)) return null;

  партия.бросок = [а, б];
  партия.кубики = а === б ? [а, а, а, а] : [а, б];
  партия.сыграно = [];
  партия.сГоловы = 0;
  партия.обязательныйКубик = null;
  партия.лимитГоловы = лимитГоловыНаХод(партия);

  /* Сколько кубиков вообще возможно сыграть. Дальше игроку будут
     показываться только перемещения, после которых это число ещё
     достижимо, — так правило «играй оба, если можешь» держится само. */
  партия.максимумКубиков = глубина(состояниеХода(партия), new Map());

  /* Играется ровно один кубик из двух разных — обязателен старший,
     если он в одиночку играется. */
  if (партия.максимумКубиков === 1 && а !== б) {
    const старший = Math.max(а, б);
    const проба = состояниеХода(партия);
    проба.кубики = [старший];
    if (шагиСостояния(проба).length > 0) партия.обязательныйКубик = старший;
  }
  return партия.бросок.slice();
}

/**
 * Сколько шашек можно снять с головы этим ходом. Обычно одну. На своём
 * первом ходу при дублях 6-6, 4-4 и 3-3 — две (смотри пункт 5 в шапке).
 */
function лимитГоловыНаХод(партия) {
  if (партия.вид !== ДЛИННЫЕ) return ФИШЕК;      // в коротких головы нет вовсе
  const [а, б] = партия.бросок;
  const первыйХод = партия.ходов[партия.ходит] === 0;
  if (первыйХод && а === б && (а === 6 || а === 4 || а === 3)) return 2;
  return 1;
}

/* =====================================================================
   ЧАСТЬ 4. ПОИСК ХОДОВ

   Перебор идёт не по настоящей партии, а по её лёгкому слепку: там
   вместо стопок имён — счётчики. Имена шашек в переборе только мешали
   бы: два одинаковых расклада, отличающиеся лишь тем, какая именно
   шашка сверху, — это одна и та же позиция, и считать её дважды глупо.
   Имена возвращаются на место в самом конце, когда шаг уже выбран.
   ===================================================================== */

/* Остатки шагов бывают от 0 (вынесена) до 25 (на баре) — значит,
   счётчиков нужно двадцать шесть. */
const ДЛИНА_ОСТАТКОВ = БАР + 1;

/** Лёгкий слепок позиции глазами того, чей сейчас ход. */
function состояниеХода(партия) {
  const цвет = партия.ходит;
  const чужой = соперник(цвет);
  const мои = new Array(ДЛИНА_ОСТАТКОВ).fill(0);
  const чужиеПоПунктам = new Array(ПУНКТОВ + 1).fill(0);
  for (let п = 1; п <= ПУНКТОВ; п++) {
    const стопка = партия.пункты[п];
    if (!стопка.length) continue;
    if (цветФишки(стопка[0]) === цвет) мои[остаток(партия.вид, цвет, п)] = стопка.length;
    else чужиеПоПунктам[п] = стопка.length;
  }
  мои[БАР] = партия.бар[цвет].length;
  мои[ВНЕ] = партия.вне[цвет].length;
  return {
    вид: партия.вид,
    цвет: цвет,
    чужой: чужой,
    мои: мои,
    чужиеПоПунктам: чужиеПоПунктам,
    чужиеВне: партия.вне[чужой].length,
    кубики: партия.кубики.slice(),
    сГоловы: партия.сГоловы,
    лимитГоловы: партия.лимитГоловы,
    обязательныйКубик: партия.обязательныйКубик
  };
}

function копияСостояния(с) {
  return {
    вид: с.вид, цвет: с.цвет, чужой: с.чужой,
    мои: с.мои.slice(),
    чужиеПоПунктам: с.чужиеПоПунктам.slice(),
    чужиеВне: с.чужиеВне,
    кубики: с.кубики.slice(),
    сГоловы: с.сГоловы,
    лимитГоловы: с.лимитГоловы,
    обязательныйКубик: с.обязательныйКубик
  };
}

/** Все ли мои шашки уже дома — только тогда разрешён вынос. */
function всеДома(с) {
  for (let ш = 7; ш <= БАР; ш++) if (с.мои[ш] > 0) return false;
  return true;
}

/** Нет ли моей шашки дальше этой: тогда её можно вынести кубиком побольше. */
function самаяДальняя(с, шагов) {
  for (let ш = шагов + 1; ш <= ПУНКТОВ; ш++) if (с.мои[ш] > 0) return false;
  return true;
}

/**
 * Все перемещения, возможные из этого слепка прямо сейчас. Перемещение
 * описано в остатках: { откуда, куда, кубик, бой, вынос }.
 * Про «обязан сыграть оба кубика» здесь ещё ничего не знают — этим
 * занимается «возможныеШаги» выше.
 */
function шагиСостояния(с) {
  const шаги = [];
  if (!с.кубики.length) return шаги;

  /* Разные значения кубиков. При дубле значение одно, и перебирать
     четыре одинаковых незачем. */
  const значения = [];
  for (const к of с.кубики) if (значения.indexOf(к) === -1) значения.push(к);

  /* Пока хоть одна моя шашка на баре — двигать можно только её.
     Это короткие нарды; в длинных бара нет и условие никогда не сработает. */
  const источники = [];
  if (с.мои[БАР] > 0) источники.push(БАР);
  else for (let ш = ПУНКТОВ; ш >= 1; ш--) if (с.мои[ш] > 0) источники.push(ш);

  const дома = всеДома(с);
  const порогБлокировки = с.вид === КОРОТКИЕ ? 2 : 1;

  for (const откуда of источники) {
    for (const кубик of значения) {
      if (с.обязательныйКубик !== null && кубик !== с.обязательныйКубик) continue;
      /* Голова длинных нард: больше положенного за ход с неё не снять. */
      if (с.вид === ДЛИННЫЕ && откуда === ПУНКТОВ && с.сГоловы >= с.лимитГоловы) continue;

      const куда = откуда - кубик;

      if (куда >= 1) {
        const целевойПункт = пунктПоОстатку(с.вид, с.цвет, куда);
        const чужих = с.чужиеПоПунктам[целевойПункт];
        if (чужих >= порогБлокировки) continue;          // пункт закрыт соперником
        /* В длинных нардах не бьют вовсе, и защищено это дважды: порог
           блокировки там равен единице, поэтому на чужую шашку просто
           не встают — до разговора о бое дело не доходит. */
        const бой = с.вид === КОРОТКИЕ && чужих === 1;
        const шаг = { откуда: откуда, куда: куда, кубик: кубик, бой: бой, вынос: false };
        if (с.вид === ДЛИННЫЕ && заборПослеШага(с, шаг)) continue;
        шаги.push(шаг);
      } else {
        /* Вынос. Точный кубик — всегда можно. Кубик больше нужного —
           только с самой дальней шашки, и только когда все дома. */
        if (!дома) continue;
        if (куда === 0 || самаяДальняя(с, откуда)) {
          шаги.push({ откуда: откуда, куда: ВНЕ, кубик: кубик, бой: false, вынос: true });
        }
      }
    }
  }
  return шаги;
}

/** Применить перемещение к лёгкому слепку. Оригинал не портится. */
function применитьКСостоянию(с, шаг) {
  const н = копияСостояния(с);
  н.мои[шаг.откуда]--;
  if (шаг.вынос) {
    н.мои[ВНЕ]++;
  } else {
    н.мои[шаг.куда]++;
    if (шаг.бой) н.чужиеПоПунктам[пунктПоОстатку(н.вид, н.цвет, шаг.куда)] = 0;
  }
  if (н.вид === ДЛИННЫЕ && шаг.откуда === ПУНКТОВ) н.сГоловы++;
  н.кубики.splice(н.кубики.indexOf(шаг.кубик), 1);
  н.обязательныйКубик = null;   // требование «играй старший» касается только первого шага
  return н;
}

/** Короткая строка-ключ слепка: по ней перебор узнаёт уже посчитанное. */
function ключСостояния(с) {
  return с.мои.join('.') + '|' + с.чужиеПоПунктам.join('.') + '|' + с.кубики.join('') +
         '|' + с.сГоловы + '|' + (с.обязательныйКубик === null ? '-' : с.обязательныйКубик);
}

/**
 * Сколько кубиков ещё удастся сыграть из этого слепка, если играть
 * наилучшим для этого образом. Это и есть механика правила «используй
 * оба кубика, если можешь»: играть разрешено только то, после чего это
 * число не падает.
 */
function глубина(с, память) {
  if (!с.кубики.length) return 0;
  const ключ = ключСостояния(с);
  const готовое = память.get(ключ);
  if (готовое !== undefined) return готовое;
  let лучшее = 0;
  for (const шаг of шагиСостояния(с)) {
    const сейчас = 1 + глубина(применитьКСостоянию(с, шаг), память);
    if (сейчас > лучшее) лучшее = сейчас;
    if (лучшее === с.кубики.length) break;   // больше всё равно не бывает
  }
  память.set(ключ, лучшее);
  return лучшее;
}

/* ---------------------------------------------------------------------
   ЗАБОР ИЗ ШЕСТИ — только длинные нарды.

   Правило словами: нельзя занять шесть пунктов подряд, если впереди
   забора нет ни одной шашки соперника. Смысл — не запереть все
   пятнадцать намертво.

   ТОНКОСТЬ, КОТОРУЮ ОБЫЧНО ПРОПУСКАЮТ. «Шесть подряд» надо считать не
   по номерам пунктов, а вдоль дороги СОПЕРНИКА. Разница вылезает в
   одном месте: у соперника дорога где-то начинается и где-то кончается,
   и шесть пунктов подряд по номерам могут оказаться тремя в самом
   начале его дороги и тремя в самом конце. Такие шесть забором не
   являются: между ними у соперника лежит вся доска, он спокойно
   проходит. Если считать по номерам, игра запретила бы совершенно
   законный ход — я на этом сам чуть не попался.

   Поэтому забор ищется по остаткам соперника: шесть подряд идущих
   чисел от 24 до 1. Вынесенные шашки соперника считаются «впереди»
   любого забора: раз хоть одна уже вышла, заперты не все пятнадцать.
   --------------------------------------------------------------------- */
function заборЗапрещён(с) {
  /* Мои пункты, переведённые в остатки соперника. */
  const занято = new Array(ПУНКТОВ + 1).fill(false);
  for (let ш = 1; ш <= ПУНКТОВ; ш++) if (с.мои[ш] > 0) занято[остатокСоперника(ш)] = true;

  /* Шашки соперника, тоже в его остатках. */
  const чужие = new Array(ПУНКТОВ + 1).fill(0);
  for (let п = 1; п <= ПУНКТОВ; п++) {
    if (с.чужиеПоПунктам[п] > 0) чужие[остаток(с.вид, с.чужой, п)] = с.чужиеПоПунктам[п];
  }

  for (let верх = ПУНКТОВ; верх >= 6; верх--) {
    let шестьПодряд = true;
    for (let i = 0; i < 6; i++) if (!занято[верх - i]) { шестьПодряд = false; break; }
    if (!шестьПодряд) continue;
    if (с.чужиеВне > 0) continue;              // хоть одна вышла — заперты не все
    const низ = верх - 5;
    let естьВпереди = false;
    for (let ш = 1; ш < низ; ш++) if (чужие[ш] > 0) { естьВпереди = true; break; }
    if (!естьВпереди) return true;
  }
  return false;
}

/** Появится ли запретный забор, если сделать это перемещение. */
function заборПослеШага(с, шаг) {
  return заборЗапрещён(применитьКСостоянию(с, шаг));
}

/* =====================================================================
   ЧАСТЬ 5. ХОД: ПО ШАГАМ И ЦЕЛИКОМ

   Наружу перемещение выходит уже с именами и номерами пунктов:

     { фишка: 'б7', откуда: 24, куда: 18, кубик: 6, побита: null, вынос: false }

   «откуда» — номер пункта либо строка 'бар'; «куда» — номер пункта либо
   строка 'вне'; «побита» — имя сбитой шашки соперника либо null.
   ===================================================================== */

/** Верхняя шашка стопки — ту и поднимаем, как рукой со стола. */
function верхняя(стопка) { return стопка.length ? стопка[стопка.length - 1] : null; }

/** Перевод внутреннего перемещения в человеческое, с именами. */
function внешнийШаг(партия, шаг) {
  const цвет = партия.ходит;
  const изБара = шаг.откуда === БАР;
  const откуда = изБара ? 'бар' : пунктПоОстатку(партия.вид, цвет, шаг.откуда);
  const фишка = изБара ? верхняя(партия.бар[цвет]) : верхняя(партия.пункты[откуда]);
  const куда = шаг.вынос ? 'вне' : пунктПоОстатку(партия.вид, цвет, шаг.куда);
  const побита = шаг.бой ? партия.пункты[куда][0] : null;
  return {
    фишка: фишка, откуда: откуда, куда: куда,
    кубик: шаг.кубик, побита: побита, вынос: шаг.вынос
  };
}

/**
 * Какие перемещения игрок может сделать прямо сейчас. Сюда уже входит
 * правило «сыграй столько кубиков, сколько можешь»: перемещения, после
 * которых часть хода пропадёт зря, не показываются вовсе.
 */
function возможныеШаги(партия) {
  if (партия.завершена || !партия.бросок || !партия.кубики.length) return [];
  const надо = партия.максимумКубиков - партия.сыграно.length;
  if (надо <= 0) return [];
  const с = состояниеХода(партия);
  const память = new Map();
  const годные = [];
  for (const шаг of шагиСостояния(с)) {
    if (1 + глубина(применитьКСостоянию(с, шаг), память) < надо) continue;
    годные.push(внешнийШаг(партия, шаг));
  }
  return годные;
}

/**
 * Найти перемещение по «откуда» и «куда» — так удобнее экрану: игрок
 * ткнул в шашку и в пункт, а какой это кубик, пусть считают правила.
 * При выносе одна и та же шашка иногда снимается и точным кубиком, и
 * кубиком побольше — берём меньший, он ценнее.
 */
function найтиШаг(партия, откуда, куда) {
  const подходящие = возможныеШаги(партия).filter(function (ш) {
    return String(ш.откуда) === String(откуда) && String(ш.куда) === String(куда);
  });
  if (!подходящие.length) return null;
  подходящие.sort(function (а, б) { return а.кубик - б.кубик; });
  return подходящие[0];
}

/**
 * Сделать одно перемещение. Принимает то, что вернули «возможныеШаги»
 * или «найтиШаг», а также простое { откуда, куда }. Возвращает
 * сделанное перемещение (с именем шашки и с именем побитой) либо null,
 * если так ходить нельзя.
 */
function сделатьШаг(партия, шаг) {
  if (!шаг) return null;
  const годные = возможныеШаги(партия);
  let выбран = null;
  for (const г of годные) {
    if (String(г.откуда) !== String(шаг.откуда) || String(г.куда) !== String(шаг.куда)) continue;
    if (шаг.кубик !== undefined && шаг.кубик !== null && г.кубик !== шаг.кубик) continue;
    if (!выбран || г.кубик < выбран.кубик) выбран = г;
  }
  if (!выбран) return null;
  применитьШаг(партия, выбран);
  return выбран;
}

/** Настоящее перемещение по доске. Сюда попадает только проверенное. */
function применитьШаг(партия, ш) {
  const цвет = партия.ходит;

  if (ш.откуда === 'бар') партия.бар[цвет].pop();
  else партия.пункты[ш.откуда].pop();

  if (ш.побита) {
    партия.пункты[ш.куда].length = 0;
    партия.бар[соперник(цвет)].push(ш.побита);
  }

  if (ш.вынос) партия.вне[цвет].push(ш.фишка);
  else партия.пункты[ш.куда].push(ш.фишка);

  партия.кубики.splice(партия.кубики.indexOf(ш.кубик), 1);
  партия.сыграно.push(ш);
  партия.обязательныйКубик = null;
  if (партия.вид === ДЛИННЫЕ && ш.откуда !== 'бар' &&
      остаток(партия.вид, цвет, ш.откуда) === ПУНКТОВ) партия.сГоловы++;

  проверитьПобеду(партия);
}

/** Доиграл ли игрок свой ход до конца (больше ходить нечем). */
function ходЗакончен(партия) {
  if (партия.завершена) return true;
  if (!партия.бросок) return false;
  return возможныеШаги(партия).length === 0;
}

/**
 * Передать ход сопернику. Если игрок ещё обязан двигать — не даст и
 * вернёт false: так нельзя «случайно» пропустить половину хода.
 */
function завершитьХод(партия) {
  if (партия.завершена) return false;
  if (!партия.бросок) return false;
  if (возможныеШаги(партия).length > 0) return false;
  партия.ходов[партия.ходит]++;
  партия.ходит = соперник(партия.ходит);
  партия.бросок = null;
  партия.кубики = [];
  партия.сыграно = [];
  партия.сГоловы = 0;
  партия.лимитГоловы = 1;
  партия.максимумКубиков = 0;
  партия.обязательныйКубик = null;
  return true;
}

/**
 * Все ходы целиком — то есть все законные способы разыграть выпавший
 * бросок до конца. Нужны боту и проверкам. Каждый ход:
 *
 *   { кубики: [6,1], шаги: [перемещение, перемещение], запись: '24/18 6/5' }
 *
 * Одинаковые по итогу способы схлопываются: боту незачем перебирать
 * «сначала шестёркой, потом единицей» и наоборот, если доска после них
 * выглядит одинаково.
 */
function возможныеХоды(партия) {
  if (партия.завершена || !партия.бросок) return [];
  const итоги = [];
  const виденные = new Set();

  function идти(п) {
    const шаги = возможныеШаги(п);
    if (!шаги.length) {
      const ключ = отпечатокПозиции(п);
      if (!виденные.has(ключ)) {
        виденные.add(ключ);
        const ход = { кубики: партия.бросок.slice(), шаги: п.сыграно.slice() };
        ход.запись = записьХода(ход);
        итоги.push(ход);
      }
      return;
    }
    for (const ш of шаги) {
      const к = копияПартии(п);
      применитьШаг(к, ш);
      идти(к);
    }
  }

  идти(копияПартии(партия));
  return итоги;
}

/**
 * Сыграть весь ход разом и передать очередь сопернику. Возвращает
 * список сделанных перемещений — по одному на кубик, ПО ПОРЯДКУ.
 * Именно этот список экран показывает по шагам, чтобы шашки ехали, а
 * не телепортировались. Не получилось — null, доска не тронута.
 */
function сделатьХод(партия, ход) {
  if (!ход || !ход.шаги) return null;
  const проба = копияПартии(партия);
  const сделанные = [];
  for (const ш of ход.шаги) {
    const вышло = сделатьШаг(проба, ш);
    if (!вышло) return null;
    сделанные.push(вышло);
  }
  if (!проба.завершена && возможныеШаги(проба).length > 0) return null;   // ход недоигран
  if (!проба.завершена) завершитьХод(проба);
  перенести(проба, партия);
  return сделанные;
}

/** Перелить содержимое одной партии в другую (снаружи объект тот же). */
function перенести(откуда, куда) {
  куда.пункты = откуда.пункты;
  куда.бар = откуда.бар;
  куда.вне = откуда.вне;
  куда.ходит = откуда.ходит;
  куда.бросок = откуда.бросок;
  куда.кубики = откуда.кубики;
  куда.сыграно = откуда.сыграно;
  куда.сГоловы = откуда.сГоловы;
  куда.лимитГоловы = откуда.лимитГоловы;
  куда.максимумКубиков = откуда.максимумКубиков;
  куда.обязательныйКубик = откуда.обязательныйКубик;
  куда.ходов = откуда.ходов;
  куда.завершена = откуда.завершена;
  куда.победитель = откуда.победитель;
  куда.цена = откуда.цена;
  куда.видПобеды = откуда.видПобеды;
  куда.причина = откуда.причина;
}

/**
 * Найти ход по записи ('24/18 13/11'). Нужно серверу: игрок присылает
 * запись, а сервер обязан убедиться, что такой ход законен, а не верить
 * присланному.
 */
function найтиХод(партия, запись) {
  const нужная = String(запись).trim();
  for (const ход of возможныеХоды(партия)) if (ход.запись === нужная) return ход;
  return null;
}

/* --- запись хода словами: '24/18', 'бар/22', '6/вне', '13/11*' --- */

function записьШага(ш) {
  return String(ш.откуда) + '/' + (ш.вынос ? 'вне' : String(ш.куда)) + (ш.побита ? '*' : '');
}

function записьХода(ход) {
  if (!ход.шаги.length) return 'пропуск';
  return ход.шаги.map(записьШага).join(' ');
}

