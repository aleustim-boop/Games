/** Не вынес ли кто-то все пятнадцать. Зовётся после каждого перемещения. */
function проверитьПобеду(партия) {
  if (партия.завершена) return;
  const цвет = партия.ходит;
  if (партия.вне[цвет].length !== ФИШЕК) return;
  записатьПобеду(партия, цвет);
}

/** Записать итог: кто выиграл, сколько это стоит и почему. */
function записатьПобеду(партия, победитель) {
  const проигравший = соперник(победитель);
  партия.завершена = true;
  партия.победитель = победитель;
  партия.цена = 1;
  партия.видПобеды = 'обычная';
  партия.причина = 'все пятнадцать шашек вынесены с доски';

  if (партия.вне[проигравший].length > 0) return;

  партия.цена = 2;
  партия.видПобеды = 'марс';
  партия.причина = 'марс: соперник не успел вынести ни одной шашки';

  /* Кокс бывает только в коротких: он опирается на бар и на дом
     победителя, а в длинных нардах ни того, ни другого нет. */
  if (партия.вид !== КОРОТКИЕ) return;
  let вДомеПобедителя = false;
  for (const п of домЦвета(партия.вид, победитель)) {
    const стопка = партия.пункты[п];
    if (стопка.length && цветФишки(стопка[0]) === проигравший) вДомеПобедителя = true;
  }
  if (партия.бар[проигравший].length > 0 || вДомеПобедителя) {
    партия.цена = 3;
    партия.видПобеды = 'кокс';
    партия.причина = 'кокс: соперник не вынес ни одной шашки и застрял на баре либо в чужом доме';
  }
}

/** Кончилась ли партия. */
function партияЗавершена(партия) { return партия.завершена; }

/** Итог партии или null, пока она идёт. */
function итог(партия) {
  if (!партия.завершена) return null;
  return {
    победитель: партия.победитель,
    цена: партия.цена,                 // 1 обычная, 2 марс, 3 кокс
    видПобеды: партия.видПобеды,
    причина: партия.причина
  };
}

