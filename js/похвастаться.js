/* =====================================================================
   Похвастаться победой: дорога к чату, общая для дурака и шашек.

   Кнопку «Похвастаться» на плашке итога рисует и подписывает сама игра
   (js/game.js у дурака, js/шашки-похвастаться.js у шашек). Этот файл —
   только дорога: как донести до чата слова о победе и ссылку на игру.
   Наружу одна дверь:

       Сеть.похвастаться(описание) → обещание { отправлено, способ }

   где способ — 'поверх' (выбор чата поверх игры, единственный путь,
   у которого «отправлено» бывает true), 'чат' (список чатов ссылкой),
   'буфер' (слова и ссылка в буфере обмена) или 'нет'. Обещание никогда
   не срывается. На чужие узлы страницы отсюда не пишется ничего.

   Почему это отдельный файл, а не часть js/сеть.js. Дорога нужна обеим
   играм, а сеть — три тысячи строк про комнаты и ходы; тащить их в шашки
   ради одной кнопки нельзя. Поэтому здесь свои маленькие помощники
   (адрес сервера, подпись Telegram, буфер обмена), а объект window.Сеть
   ДОПОЛНЯЕТСЯ: на странице дурака полный js/сеть.js кладёт в него всё
   остальное, и порядок подключения двух файлов не важен.

   Три пути к чату, от лучшего к запасному, — те же, что у «Позвать друга»:
     1) сервер готовит сообщение (только он знает токен бота), Telegram
        показывает выбор чата ПОВЕРХ игры и никуда не уводит;
     2) на телефоне — список чатов ссылкой t.me/share/url;
     3) иначе — слова и ссылка в буфер обмена.
   Про внутренние неудачи человеку не рассказываем: он просто получает
   ссылку способом попроще.

   Слова о победе собирает сервер сам по полям описания — чужой текст бот
   не рассылает. Готовые слова из описания идут только в запасные пути.
   ===================================================================== */

'use strict';

(function () {

  /* Имя бота и короткое имя мини-приложения — те же, что в js/сеть.js
     (там они нужны для приглашений за стол). Заменят бота — править в обоих
     файлах; хвостик «?приглашение=бот/приложение» в адресе игры сильнее. */
  const ИМЯ_БОТА = 'BoardingGames_bot';
  const ИМЯ_ПРИЛОЖЕНИЯ = 'BoardGames';

  /* Метка игры в startapp — та же, что разбирает js/сеть.js. Дурак без
     метки: старые ссылки вели в него и ведут. Шашки — со словом, иначе
     Telegram откроет index.html, то есть карты, под сообщением про шашки. */
  const МЕТКИ_ИГР = { 'дурак': '', 'шашки': 'shashki' };

  /* Адрес сервера. На странице дурака его знает полный js/сеть.js — у него
     и спрашиваем. Без него — те же источники в том же порядке: хвостик
     ссылки, вписанный руками адрес, запасной. */
  /* Имя ключа латиницей — то же самое, что в js/сеть.js: адрес сервера
     один на весь сборник, и читают его отсюда и оттуда. Старое имя тоже
     помним: переезд делает js/сеть.js, но эта страница может открыться
     и без него, а адрес нужен всё равно. */
  const КЛЮЧ_АДРЕСА = 'server_address';
  const СТАРЫЙ_КЛЮЧ_АДРЕСА = 'подкидной-дурак:адрес-сервера';
  const АДРЕС_ПО_УМОЛЧАНИЮ = 'http://127.0.0.1:8765';

  /* Сколько ждём подготовку сообщения сервером. Дальше — запасной путь. */
  const ЖДЁМ_ПОДГОТОВКУ = 2500;

  /* Слова, если игра прислала описание без них. Не должно случаться —
     но пустое сообщение в чате хуже общего. */
  const СЛОВА_ПО_УМОЛЧАНИЮ = 'Победа. Сыграем?';

  /* ---------- Страница и Telegram ---------- */

  /** Значение из адреса страницы — из «?…», потом из «#…» (туда пишет Telegram). */
  function изАдресаСтраницы(имена) {
    const место = window.location || {};
    for (const часть of [String(место.search || ''), String(место.hash || '')]) {
      try {
        const разбор = new URLSearchParams(часть.replace(/^[?#]/, ''));
        for (const имя of имена) {
          const значение = разбор.get(имя);
          if (значение) return значение;
        }
      } catch (сбой) {
        /* разбора адресов нет — считаем, что параметра нет */
      }
    }
    return '';
  }

  /** Имя бота и приложения: хвостик «?приглашение=» сильнее констант. */
  function именаДляСсылки() {
    const хвостик = String(изАдресаСтраницы(['приглашение', 'invite']) || '').trim();
    const части = хвостик.split('/').filter(Boolean);
    const бот = (части.length > 1 ? части[0] : ИМЯ_БОТА).replace(/^@/, '');
    const приложение = части.length > 1 ? части[1] : (части[0] || ИМЯ_ПРИЛОЖЕНИЯ);
    return { бот: бот, приложение: приложение };
  }

  function приложениеTelegram() {
    try {
      return (window.Telegram && window.Telegram.WebApp) || null;
    } catch (сбой) {
      return null;
    }
  }

  /** Подпись Telegram — по ней сервер узнаёт, кто просит. Нет — пусто. */
  function подписьTelegram() {
    const приложение = приложениеTelegram();
    return (приложение && приложение.initData) || '';
  }

  /** Игра открыта внутри Telegram, а не просто в браузере. */
  function мыВTelegram() {
    const приложение = приложениеTelegram();
    if (!приложение) return false;
    if (приложение.initData) return true;
    const площадка = String(приложение.platform || '');
    return Boolean(площадка) && площадка !== 'unknown';
  }

  /** 'телефон', 'компьютер' или '' — не в Telegram. На компьютере список чатов уводит игру с экрана. */
  function гдеМыВTelegram() {
    if (!мыВTelegram()) return '';
    const площадка = String(приложениеTelegram().platform || '').toLowerCase();
    return (площадка === 'android' || площадка === 'ios') ? 'телефон' : 'компьютер';
  }

  /** Умеет ли этот Telegram показывать выбор чата поверх игры. */
  function можноВыбратьЧатПоверх() {
    const приложение = приложениеTelegram();
    if (!приложение || typeof приложение.shareMessage !== 'function') return false;
    if (!приложение.initData) return false;   // без подписи сервер не поверит
    return typeof приложение.isVersionAtLeast === 'function' && приложение.isVersionAtLeast('8.0');
  }

  /* ---------- Адрес сервера и запрос ---------- */

  function адресСервера() {
    if (window.Сеть && typeof window.Сеть.адрес === 'function') {
      try {
        const адрес = window.Сеть.адрес();
        if (адрес) return адрес;
      } catch (сбой) {
        /* спросим по-своему */
      }
    }
    const изСсылки = изАдресаСтраницы(['сервер', 'server']);
    if (изСсылки) return изСсылки.replace(/\/+$/, '');
    try {
      /* Сперва новое имя, потом старое. Второе читаем нарочно: страница
         могла открыться без js/сеть.js, который перевозит значение, —
         а без адреса «Похвастаться» молча уходит на запасной сервер. */
      const вписан = (window.localStorage.getItem(КЛЮЧ_АДРЕСА) ||
                      window.localStorage.getItem(СТАРЫЙ_КЛЮЧ_АДРЕСА) || '').trim();
      if (вписан) return вписан.replace(/\/+$/, '');
    } catch (сбой) {
      /* память закрыта — идём на запасной */
    }
    return АДРЕС_ПО_УМОЛЧАНИЮ;
  }

  /** Один запрос серверу. Не падает: любая беда — { ок: false }. */
  function запрос(путь, тело) {
    const управление = typeof AbortController !== 'undefined' ? new AbortController() : null;
    const сторож = setTimeout(function () { if (управление) управление.abort(); }, ЖДЁМ_ПОДГОТОВКУ);
    const настройки = {
      method: 'POST',
      // Второй заголовок — пропуск через туннель, как у js/сеть.js.
      headers: { 'Content-Type': 'application/json', 'bypass-tunnel-reminder': 'true' },
      body: JSON.stringify(тело || {})
    };
    if (управление) настройки.signal = управление.signal;
    return fetch(адресСервера() + путь, настройки)
      .then(function (ответ) {
        return ответ.json().then(
          function (данные) { return { ок: ответ.ok, данные: данные && typeof данные === 'object' ? данные : {} }; },
          function () { return { ок: false, данные: {} }; }
        );
      })
      .catch(function () { return { ок: false, данные: {} }; })
      .then(function (итог) {
        clearTimeout(сторож);
        return итог;
      });
  }

  /* ---------- Буфер обмена и список чатов ---------- */

  function скопироватьЧерезПоле(текст) {
    try {
      const поле = document.createElement('textarea');
      поле.value = текст;
      поле.setAttribute('readonly', '');
      поле.style.position = 'fixed';
      поле.style.top = '-1000px';
      document.body.appendChild(поле);
      поле.select();
      if (поле.setSelectionRange) поле.setSelectionRange(0, текст.length);   // iPhone
      const вышло = document.execCommand && document.execCommand('copy');
      document.body.removeChild(поле);
      return Boolean(вышло);
    } catch (сбой) {
      return false;
    }
  }

  function положитьВБуфер(текст) {
    const буфер = window.navigator && window.navigator.clipboard;
    if (буфер && typeof буфер.writeText === 'function') {
      try {
        return буфер.writeText(текст).then(
          function () { return true; },
          function () { return скопироватьЧерезПоле(текст); }
        );
      } catch (сбой) {
        return Promise.resolve(скопироватьЧерезПоле(текст));
      }
    }
    return Promise.resolve(скопироватьЧерезПоле(текст));
  }

  /** Список чатов средствами Telegram. Отвечает, получилось ли открыть. */
  function открытьВыборЧата(ссылка, слова) {
    const приложение = приложениеTelegram();
    if (!приложение || typeof приложение.openTelegramLink !== 'function') return false;
    try {
      приложение.openTelegramLink('https://t.me/share/url?url=' + encodeURIComponent(ссылка) +
                                  '&text=' + encodeURIComponent(слова));
      return true;
    } catch (сбой) {
      return false;
    }
  }

  /* ---------- Сама дорога ---------- */

  /**
   * Ссылка на игру, без кода комнаты. Из Telegram — мини-приложение
   * (с меткой игры, если это не дурак); из браузера — эта же страница
   * без хвостиков. Ни той, ни другой не выходит — пусто.
   */
  function ссылкаНаИгру(игра) {
    const имена = именаДляСсылки();
    const метка = МЕТКИ_ИГР[игра] || '';
    const телеграмная = имена.бот && имена.приложение
      ? 'https://t.me/' + имена.бот + '/' + имена.приложение + (метка ? '?startapp=' + метка : '')
      : '';
    const место = window.location || {};
    let браузерная = '';
    if (String(место.protocol || '') !== 'file:') {
      const начало = место.origin || (String(место.protocol || '') + '//' + String(место.host || ''));
      if (начало && начало !== 'null//') браузерная = начало + String(место.pathname || '');
    }
    if (мыВTelegram()) return телеграмная || браузерная;
    return браузерная || телеграмная;
  }

  /** Что уходит серверу: поля описания, без свободного текста. */
  function телоПохвальбы(описание, ссылка) {
    return {
      initData: подписьTelegram(),
      ссылка: ссылка,
      вид: 'победа',
      игра: описание.игра,
      исход: описание.исход,
      соперники: описание.соперники,
      уровень: описание.уровень,
      игроков: описание.игроков,
      парами: описание.парами === true,
      переводной: описание.переводной === true,
      серия: описание.серия
    };
  }

  /** Лучший путь: сервер готовит сообщение, Telegram показывает выбор чата поверх игры. */
  function похвастатьсяЧерезTelegram(описание, ссылка) {
    return new Promise(function (готово) {
      let ответили = false;
      const закончить = function (что) {
        if (ответили) return;
        ответили = true;
        готово(что);
      };
      setTimeout(function () { закончить({ отправлено: false, способ: 'нет' }); }, ЖДЁМ_ПОДГОТОВКУ);

      запрос('/приглашение', телоПохвальбы(описание, ссылка)).then(function (ответ) {
        if (!ответ.ок || ответ.данные.ок !== true || !ответ.данные.номерСообщения) {
          return закончить({ отправлено: false, способ: 'нет' });
        }
        try {
          приложениеTelegram().shareMessage(ответ.данные.номерСообщения, function (отправлено) {
            закончить({ отправлено: отправлено === true, способ: 'поверх' });
          });
        } catch (сбой) {
          закончить({ отправлено: false, способ: 'нет' });
        }
      });
    });
  }

  /** Запасной путь: на телефоне список чатов, иначе буфер. Отправил ли человек — не видно. */
  function похвастатьсяПоСтаринке(слова, ссылка) {
    if (гдеМыВTelegram() === 'телефон' && открытьВыборЧата(ссылка, слова)) {
      return Promise.resolve({ отправлено: false, способ: 'чат' });
    }
    return положитьВБуфер(слова + ' ' + ссылка).then(function (вышло) {
      return { отправлено: false, способ: вышло ? 'буфер' : 'нет' };
    });
  }

  /**
   * Похвастаться победой. Описание — от игры: { игра, исход, соперники,
   * уровень, игроков, парами, переводной, серия, слова }. Никогда
   * не срывается: любая беда — { отправлено: false, способ: 'нет' }.
   */
  function похвастаться(описание) {
    const что = описание && typeof описание === 'object' ? описание : {};
    const слова = typeof что.слова === 'string' && что.слова ? что.слова : СЛОВА_ПО_УМОЛЧАНИЮ;
    let ссылка = '';
    try {
      ссылка = ссылкаНаИгру(что.игра);
    } catch (сбой) {
      ссылка = '';
    }
    if (!ссылка) return Promise.resolve({ отправлено: false, способ: 'нет' });

    const ничего = { отправлено: false, способ: 'нет' };
    const поСтаринке = function () {
      return похвастатьсяПоСтаринке(слова, ссылка).catch(function () { return ничего; });
    };
    if (можноВыбратьЧатПоверх() && ссылка.indexOf('https://t.me/') === 0) {
      return похвастатьсяЧерезTelegram(что, ссылка)
        .then(function (итог) { return итог.способ === 'нет' ? поСтаринке() : итог; })
        .catch(поСтаринке);
    }
    return поСтаринке();
  }

  // Дополняем, а не заводим заново: полный js/сеть.js кладёт сюда своё.
  window.Сеть = window.Сеть || {};
  window.Сеть.похвастаться = похвастаться;

})();
