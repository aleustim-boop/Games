'use strict';

/* =====================================================================
   ШАШКИ — СОПЕРНИК-РОБОТ.

   Своих правил у бота нет ни одного. Какие ходы возможны, кончилась ли
   партия, чей ход — на всё это отвечает js/шашки-правила.js. Отдельной
   двери «для бота» в правилах тоже нет: он берёт ровно то же, что видит
   человек на экране. В шашках подглядывать вроде и нечего — доска
   открыта, — но правило проекта одно на все игры, и держать его надо
   там, где оно ничего не стоит, иначе в следующей игре его нарушат.

   Как бот думает:

     1. ОЦЕНКА. Смотрит на позицию и выдаёт число: насколько она хороша
        для белых. Больше нуля — белым лучше.
     2. ПЕРЕБОР. Проигрывает ходы вперёд на несколько шагов и выбирает
        тот, после которого при лучшей игре соперника позиция всё равно
        останется хорошей (альфа-бета — обычный перебор, который не
        досматривает заведомо плохие ветки).
     3. ДОСЧЁТ БОЁВ. Останавливаться посреди размена нельзя: бот увидит
        «я забрал шашку» и не увидит, что её сейчас заберут обратно.
        Поэтому пока на доске есть бой, счёт продолжается до тишины.
        В русских шашках это дёшево: если бой есть, он обязателен, и
        других ходов просто не существует.
     4. УГЛУБЛЕНИЕ ПО ШАГАМ. Сначала считает на один ход вперёд, потом
        на два, на три — и так пока не кончится отпущенное время. Лучший
        ход с последней досчитанной глубины всегда наготове, поэтому
        часы можно остановить в любой миг.

   Почему по шагам, а не одним куском: пока бот считает, страница не
   рисуется вовсе. Рабочий поток (Web Worker) эту беду решил бы, но он
   не работает, когда файл открыт с диска двойным кликом, — а это наше
   требование. Значит, считаем короткими кусками и между ними отдаём
   управление экрану.

   Файл читается и браузером (window.ШашкиБот), и Node (module.exports):
   в Node по нему гоняют замеры силы уровней.
   ===================================================================== */

(function () {
  const Правила = (typeof window !== 'undefined' && window.ШашкиПравила) ||
                  (typeof require !== 'undefined' ? require('./шашки-правила.js') : null);

  if (!Правила) {
    throw new Error('js/шашки-бот.js не нашёл правил — подключите js/шашки-правила.js раньше бота');
  }

  /* ==================================================================
     ЧАСТЬ 1. УРОВНИ

     Три уровня отличаются ровно двумя вещами: как глубоко бот считает
     и как часто нарочно ошибается. Всё остальное у них общее — иначе
     получились бы три разных бота, и разницу между ними никто не смог
     бы объяснить.
     ================================================================== */

  const УРОВНИ = ['лёгкий', 'обычный', 'сложный'];
  const УРОВЕНЬ_ПО_УМОЛЧАНИЮ = 'обычный';

  const НАСТРОЙКИ_УРОВНЕЙ = {
    /* Лёгкий смотрит ровно на один свой ход вперёд и не спрашивает себя,
       что ответит соперник. Поэтому он с радостью берёт подставленную
       шашку и отдаёт три — то есть играет как живой новичок, и новичок
       его обыгрывает. Вдобавок он каждый третий ход выбирает наугад:
       без этого он всегда играет одно и то же и его быстро разгадывают. */
    'лёгкий':  { глубина: 1,  доляОшибок: 0.35, бюджетМс: 0,   таблица: false },
    /* Обычный считает на четыре полухода с досчётом разменов. Двойной
       удар видит, длинную комбинацию — нет. */
    'обычный': { глубина: 4,  доляОшибок: 0,    бюджетМс: 0,   таблица: false },
    /* Сложный углубляется по шагам, пока не кончится треть секунды,
       и помнит уже посчитанные позиции. */
    'сложный': { глубина: 14, доляОшибок: 0,    бюджетМс: 300, таблица: true }
  };

  /** Незнакомое слово превращаем в «обычный», чтобы опечатка не роняла игру. */
  function проверитьУровень(слово) {
    return УРОВНИ.indexOf(слово) !== -1 ? слово : УРОВЕНЬ_ПО_УМОЛЧАНИЮ;
  }

  function настройкиУровня(что) {
    const набор = (что && typeof что === 'object') ? что : { уровень: что };
    const уровень = проверитьУровень(набор.уровень);
    const основа = НАСТРОЙКИ_УРОВНЕЙ[уровень];
    return {
      уровень: уровень,
      глубина: основа.глубина,
      доляОшибок: основа.доляОшибок,
      бюджетМс: основа.бюджетМс,
      таблица: основа.таблица,
      // Случайность передаётся снаружи: тогда замер можно повторить.
      случайное: typeof набор.случайное === 'function' ? набор.случайное : Math.random
    };
  }

  /* ==================================================================
     ЧАСТЬ 2. ОЦЕНКА ПОЗИЦИИ

     Откуда взялись веса — честно. Сами числа взяты из обычной шашечной
     практики (материал, продвижение, задний ряд, край), а не подобраны
     замером: замер на 80 партий разницы между соседними значениями
     не различает, у него погрешность около 11 очков из 100. Проверено
     замером другое, и это главное: что оценка в целом НЕ СЛОМАНА —
     см. монотонность ниже.

     Править эти числа на глаз всё равно нельзя. В дураке на этом уже
     обожглись: «сложный» годами был неотличим от обычного из-за одной
     строчки, и никто не замечал. Правило простое: одно изменение за
     раз, и обязательно с замером — иначе неизвестно, стало лучше или
     хуже.

     Признак, что оценка не сломана: бот с бо́льшей глубиной обязан
     обыгрывать бота с меньшей. Если не обыгрывает — сломана оценка,
     а не глубина.
     ================================================================== */

  const ЦЕНА_ПРОСТОЙ = 100;
  /* Дамка ходит и бьёт на любое расстояние в обе стороны, поэтому стоит
     заметно больше простой.

     Точное число замером выбрать НЕ удалось, и это надо знать честно:
     стравливали три бота с ценой дамки 250, 300 и 400 на глубине 4,
     по 80 партий на пару со сменой цвета. Вышло 51,2 / 48,1 / 52,5
     очка из 100 при погрешности около 11 — то есть все три одинаковы,
     разницы замер не видит. Оставили 300 как середину. Если кто-то
     соберётся это число править — сначала замер побольше, иначе
     правка будет ничем не лучше нынешнего значения. */
  const ЦЕНА_ДАМКИ = 300;
  /* За каждый ряд, пройденный к дамкам. Простая на пороге превращения
     дороже той, что стоит дома. */
  const ЗА_ПРОДВИЖЕНИЕ = 4;
  /* Своя первая горизонталь: пока шашки стоят дома, сопернику некуда
     проходить в дамки. Классическое соображение шашечной игры. */
  const ЗА_ЗАДНИЙ_РЯД = 6;
  /* Шашку на крайней вертикали (a и h) нельзя перепрыгнуть сбоку —
     её просто нечем бить с той стороны. Зато и ходов у неё меньше. */
  const ЗА_КРАЙ = 4;

  const ПОБЕДА = 100000;      // с чем сравнивать нечего: партия выиграна

  /* Разбор имени поля — это не правило игры, а всего лишь чтение
     подписи «c3». Правила сами обещают такие имена в договоре. */
  function рядПоля(поле) { return Number(поле[1]); }
  function наКраю(поле) { return поле[0] === 'a' || поле[0] === 'h'; }

  /**
   * Насколько позиция хороша ДЛЯ БЕЛЫХ. Больше нуля — белым лучше,
   * меньше — чёрным. Ноль — поровну.
   */
  function оценить(партия) {
    let очки = 0;
    for (const поле of Правила.ПОЛЯ) {
      const что = Правила.фишка(партия, поле);
      if (!что) continue;
      const белая = что.цвет === Правила.БЕЛЫЕ;
      let цена;
      if (что.дамка) {
        цена = ЦЕНА_ДАМКИ;
      } else {
        // Сколько рядов простая уже прошла к дамкам: 0 — стоит дома.
        const продвижение = белая ? рядПоля(поле) - 1 : 8 - рядПоля(поле);
        цена = ЦЕНА_ПРОСТОЙ + продвижение * ЗА_ПРОДВИЖЕНИЕ;
        if (продвижение === 0) цена += ЗА_ЗАДНИЙ_РЯД;
      }
      if (наКраю(поле)) цена += ЗА_КРАЙ;
      очки += белая ? цена : -цена;
    }
    return очки;
  }

  /** Та же оценка, но глазами того, чей сейчас ход. */
  function оценитьДляХодящего(партия) {
    const очки = оценить(партия);
    return Правила.чейХод(партия) === Правила.БЕЛЫЕ ? очки : -очки;
  }

  /* ==================================================================
     ЧАСТЬ 3. ПОРЯДОК ХОДОВ

     Альфа-бета тем сильнее срезает лишнее, чем раньше встречает хороший
     ход. Поэтому перед перебором ходы раскладываем: сначала самые
     многообещающие.
     ================================================================== */

  /** Короткое имя хода — чтобы узнать его в записанной таблице. */
  function ключХода(ход) {
    return ход.откуда + ход.куда + ход.побитые.join('');
  }

  /** Грубая цена хода до всякого перебора: чем больше, тем раньше смотрим. */
  function весХода(ход) {
    let вес = ход.побитые.length * 100;
    if (ход.станетДамкой) вес += 60;
    return вес;
  }

  /*
   * Разложить ходы по убыванию обещания. Если передать «случайное»,
   * список сперва тасуется — так делают только в корне.
   *
   * Зачем тасовать. Из нескольких одинаково хороших ходов надо брать
   * разные, иначе бот в одинаковых позициях всегда играет одно и то же
   * и партия против него превращается в заученный урок. Раньше для
   * этого копился список «равных лучших» — и это была ошибка: при
   * альфа-бете отсечённый ход возвращает не точную оценку, а границу,
   * и она сплошь и рядом в точности равна альфе. Заведомо худшие ходы
   * попадали в список равных, и бот выбирал их наугад. Чем глубже счёт,
   * тем чаще отсечения, поэтому глубина 6 переставала быть сильнее
   * глубины 4 (замерено: 51,7 очка из 100 вместо ожидаемых 60+).
   * Тасовка даёт ту же пестроту без вранья: сортировка устойчива,
   * поэтому ходы с равным весом сохраняют перетасованный порядок,
   * а выбирается из них честно первый.
   */
  function упорядочить(ходы, ключЛучшего, случайное) {
    const список = ходы.slice();
    if (случайное) {
      for (let i = список.length - 1; i > 0; i--) {
        const j = Math.floor(случайное() * (i + 1));
        const в = список[i]; список[i] = список[j]; список[j] = в;
      }
    }
    список.sort(function (а, б) { return весХода(б) - весХода(а); });
    if (!ключЛучшего) return список;
    // Ход, который в прошлый раз оказался лучшим, смотрим первым.
    const где = список.findIndex(function (х) { return ключХода(х) === ключЛучшего; });
    if (где > 0) список.unshift(список.splice(где, 1)[0]);
    return список;
  }

  /* ==================================================================
     ЧАСТЬ 4. ПЕРЕБОР
     ================================================================== */

  const ТОЧНО = 0;        // счёт посчитан точно
  const НЕ_МЕНЬШЕ = 1;    // счёт не меньше записанного (ветку срезали снизу)
  const НЕ_БОЛЬШЕ = 2;    // счёт не больше записанного
  const ПРОВЕРКА_ЧАСОВ = 512;   // как часто заглядывать на часы, в узлах
  const ЗАПАС_ДОСЧЁТА = 12;     // до скольких лишних полуходов досчитывать бои

  /** Рабочая тетрадь одного счёта: узлы, часы, таблица позиций. */
  function завестиТетрадь(настройки, срок) {
    return {
      узлов: 0,
      срок: срок,
      прервано: false,
      таблица: настройки.таблица ? new Map() : null
    };
  }

  function времяВышло(тетрадь) {
    if (тетрадь.срок === 0) return false;
    if ((тетрадь.узлов % ПРОВЕРКА_ЧАСОВ) !== 0) return тетрадь.прервано;
    if (Date.now() >= тетрадь.срок) тетрадь.прервано = true;
    return тетрадь.прервано;
  }

  /**
   * Счёт позиции глазами того, чей ход. Возвращает число очков.
   *
   * «отКорня» — сколько полуходов от нынешней позиции мы уже отошли.
   * Он нужен, чтобы выигрыш через два хода ценился выше выигрыша через
   * шесть: иначе бот видит, что выигрывает, и тянет резину.
   */
  function перебор(партия, глубина, альфа, бета, отКорня, запасДосчёта, тетрадь) {
    тетрадь.узлов++;
    if (времяВышло(тетрадь)) return 0;

    if (Правила.партияЗавершена(партия)) {
      const результат = Правила.итог(партия);
      if (результат.ничья) return 0;
      /* Партия кончилась не ничьёй — значит ходить было некому, и это
         проигрыш того, чей сейчас ход. Про «кто победил» спрашивать
         не нужно: победитель всегда другой. */
      return -(ПОБЕДА - отКорня);
    }

    const естьБой = Правила.естьБой(партия);
    // Досчитываем бои до тишины: обрывать размен посередине нельзя.
    const пораОстановиться = глубина <= 0 && (!естьБой || запасДосчёта <= 0);
    if (пораОстановиться) return оценитьДляХодящего(партия);

    const отпечаток = тетрадь.таблица ? Правила.отпечатокПозиции(партия) : null;
    let ключЛучшего = null;
    if (отпечаток !== null) {
      const запись = тетрадь.таблица.get(отпечаток);
      if (запись) {
        ключЛучшего = запись.ключХода;
        if (запись.глубина >= глубина) {
          if (запись.вид === ТОЧНО) return запись.очки;
          if (запись.вид === НЕ_МЕНЬШЕ && запись.очки > альфа) альфа = запись.очки;
          if (запись.вид === НЕ_БОЛЬШЕ && запись.очки < бета) бета = запись.очки;
          if (альфа >= бета) return запись.очки;
        }
      }
    }

    const альфаБыла = альфа;
    // Пока идёт досчёт боёв, глубина уже нулевая — тратим запас досчёта.
    const следующаяГлубина = глубина > 0 ? глубина - 1 : 0;
    const следующийЗапас = глубина > 0 ? запасДосчёта : запасДосчёта - 1;

    let лучшиеОчки = -ПОБЕДА - 1;
    let лучшийКлюч = null;

    for (const ход of упорядочить(Правила.возможныеХоды(партия), ключЛучшего)) {
      const копия = Правила.копияПартии(партия);
      Правила.сделатьХод(копия, ход);
      const очки = -перебор(копия, следующаяГлубина, -бета, -альфа,
                            отКорня + 1, следующийЗапас, тетрадь);
      if (тетрадь.прервано) return 0;
      if (очки > лучшиеОчки) {
        лучшиеОчки = очки;
        лучшийКлюч = ключХода(ход);
      }
      if (очки > альфа) альфа = очки;
      if (альфа >= бета) break;      // соперник сюда не пойдёт, дальше не смотрим
    }

    if (отпечаток !== null && !тетрадь.прервано) {
      /* Счёт «тут выигрыш» нельзя хранить как обычное число: в нём
         записано, ЧЕРЕЗ СКОЛЬКО ходов выигрыш, и считается это от
         нынешней позиции. Та же позиция встретится в другом месте
         дерева на другом расстоянии — и записанное число окажется
         враньём. Поэтому у таких записей ставим глубину -1: подсказку
         про лучший ход из них берём (она верна всегда), а счёт из них
         не берётся никогда, потому что требуемая глубина всегда 0 и
         больше. Без этого бот, увидев выигрыш, начинал топтаться
         на месте вместо того, чтобы дожать. */
      const этоВыигрышИлиПроигрыш = Math.abs(лучшиеОчки) >= ПОБЕДА - 1000;
      тетрадь.таблица.set(отпечаток, {
        глубина: этоВыигрышИлиПроигрыш ? -1 : глубина,
        очки: лучшиеОчки,
        вид: лучшиеОчки <= альфаБыла ? НЕ_БОЛЬШЕ : (альфа >= бета ? НЕ_МЕНЬШЕ : ТОЧНО),
        ключХода: лучшийКлюч
      });
    }
    return лучшиеОчки;
  }

  /**
   * Разобрать все ходы из позиции на одну глубину и вернуть лучший.
   * Возвращает { ход, очки, узлов, успел }. «успел: false» значит, что
   * время кончилось посреди счёта и доверять этой глубине нельзя.
   */
  function перебратьКорень(партия, глубина, тетрадь, ключЛучшего, случайное) {
    const ходы = упорядочить(Правила.возможныеХоды(партия), ключЛучшего, случайное);
    if (ходы.length === 0) return { ход: null, очки: 0, успел: true };

    let альфа = -ПОБЕДА - 1;
    let лучший = ходы[0];
    let лучшиеОчки = -ПОБЕДА - 1;

    for (const ход of ходы) {
      const копия = Правила.копияПартии(партия);
      Правила.сделатьХод(копия, ход);
      const очки = -перебор(копия, глубина - 1, -ПОБЕДА - 1, -альфа, 1, ЗАПАС_ДОСЧЁТА, тетрадь);
      if (тетрадь.прервано) return { ход: null, очки: 0, успел: false };
      /* Строго больше, а не «больше либо равно»: ход с оценкой РОВНО
         в альфу мог просто не досчитаться до конца — доверять ему нельзя.
         Пестроту даёт тасовка списка выше, а не выбор из границ. */
      if (очки > лучшиеОчки) {
        лучшиеОчки = очки;
        лучший = ход;
      }
      if (очки > альфа) альфа = очки;
    }

    return { ход: лучший, очки: лучшиеОчки, успел: true };
  }

  /* ==================================================================
     ЧАСТЬ 5. ВЫБОР ХОДА
     ================================================================== */

  /** Ход наугад — им лёгкий уровень нарочно портит себе игру. */
  function ходНаугад(партия, случайное) {
    const ходы = Правила.возможныеХоды(партия);
    return ходы[Math.floor(случайное() * ходы.length)] || null;
  }

  /**
   * Выбрать ход сразу, не отдавая управления экрану. Нужно замерам
   * и коротким уровням; экран пользуется «думать».
   */
  function выбратьХодСразу(партия, что) {
    const настройки = настройкиУровня(что);
    if (Правила.партияЗавершена(партия)) return null;
    const ходы = Правила.возможныеХоды(партия);
    if (ходы.length === 0) return null;
    if (ходы.length === 1) return ходы[0];      // выбирать не из чего

    if (настройки.доляОшибок > 0 && настройки.случайное() < настройки.доляОшибок) {
      return ходНаугад(партия, настройки.случайное);
    }

    const срок = настройки.бюджетМс > 0 ? Date.now() + настройки.бюджетМс : 0;
    const тетрадь = завестиТетрадь(настройки, срок);
    let лучший = ходы[0];
    let ключ = null;
    for (let глубина = 1; глубина <= настройки.глубина; глубина++) {
      const шаг = перебратьКорень(партия, глубина, тетрадь, ключ, настройки.случайное);
      if (!шаг.успел) break;
      лучший = шаг.ход;
      ключ = ключХода(шаг.ход);
      if (Math.abs(шаг.очки) >= ПОБЕДА - 100) break;   // выигрыш найден, глубже незачем
      if (срок !== 0 && Date.now() >= срок) break;
    }
    return лучший;
  }

  /**
   * Думать кусочками и позвать «готово(ход)», когда решит.
   *
   * Между глубинами управление возвращается браузеру: он успевает
   * перерисовать экран, и человек видит, что игра жива. Первый кусок
   * тоже отложен — чтобы надпись «соперник думает» успела появиться
   * ДО того, как начнётся счёт.
   */
  function думать(партия, что, готово) {
    const настройки = настройкиУровня(что);
    const ответить = function (ход) {
      if (typeof готово === 'function') готово(ход);
    };

    if (Правила.партияЗавершена(партия)) { отложить(function () { ответить(null); }); return; }
    const ходы = Правила.возможныеХоды(партия);
    if (ходы.length === 0) { отложить(function () { ответить(null); }); return; }
    if (ходы.length === 1) { отложить(function () { ответить(ходы[0]); }); return; }

    if (настройки.доляОшибок > 0 && настройки.случайное() < настройки.доляОшибок) {
      const наугад = ходНаугад(партия, настройки.случайное);
      отложить(function () { ответить(наугад); });
      return;
    }

    const срок = настройки.бюджетМс > 0 ? Date.now() + настройки.бюджетМс : 0;
    const тетрадь = завестиТетрадь(настройки, срок);
    let лучший = ходы[0];
    let ключ = null;
    let глубина = 1;

    function кусок() {
      const шаг = перебратьКорень(партия, глубина, тетрадь, ключ, настройки.случайное);
      const хватит = !шаг.успел ||
                     глубина >= настройки.глубина ||
                     Math.abs(шаг.очки) >= ПОБЕДА - 100 ||
                     (срок !== 0 && Date.now() >= срок);
      if (шаг.успел) {
        лучший = шаг.ход;
        ключ = ключХода(шаг.ход);
      }
      if (хватит) { ответить(лучший); return; }
      глубина++;
      отложить(кусок);
    }
    отложить(кусок);
  }

  /* Отложить работу так, чтобы экран успел перерисоваться.
     В Node таймера ждать незачем, но он там тоже есть — код один. */
  function отложить(дело) {
    setTimeout(дело, 0);
  }

  /**
   * Лучший ход строго на заданную глубину, без бюджета времени и без
   * нарочных ошибок. Нужен проверке монотонности: бот с глубиной 6
   * обязан обыгрывать бота с глубиной 4, иначе сломана оценка.
   */
  function лучшийХодНаГлубину(партия, глубина, случайное) {
    if (Правила.партияЗавершена(партия)) return null;
    const бросок = typeof случайное === 'function' ? случайное : Math.random;
    const тетрадь = завестиТетрадь({ таблица: true }, 0);
    let лучший = null;
    let ключ = null;
    for (let г = 1; г <= глубина; г++) {
      const шаг = перебратьКорень(партия, г, тетрадь, ключ, бросок);
      if (!шаг.ход) break;
      лучший = шаг.ход;
      ключ = ключХода(шаг.ход);
      if (Math.abs(шаг.очки) >= ПОБЕДА - 100) break;
    }
    return лучший;
  }

  /* ==================================================================
     ЧАСТЬ 6. ЧТО ФАЙЛ ОТДАЁТ НАРУЖУ
     ================================================================== */

  const Бот = {
    УРОВНИ: УРОВНИ,
    УРОВЕНЬ_ПО_УМОЛЧАНИЮ: УРОВЕНЬ_ПО_УМОЛЧАНИЮ,
    думать: думать,
    выбратьХодСразу: выбратьХодСразу,
    лучшийХодНаГлубину: лучшийХодНаГлубину,
    оценить: оценить
  };

  if (typeof module !== 'undefined' && module.exports) module.exports = Бот;
  if (typeof window !== 'undefined') window.ШашкиБот = Бот;
})();
