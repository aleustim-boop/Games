'use strict';

/* =====================================================================
   ШАХМАТЫ — ЭКРАН. Рисует доску и слушает палец.

   Своих правил у этого файла НЕТ ни одного. Он не знает, как ходит конь,
   когда можно рокироваться, что такое взятие на проходе и чем мат
   отличается от пата: на каждый такой вопрос отвечает
   js/шахматы-правила.js. Здесь только «что показать» и «куда ткнули».

   Так сделано не из красоты. Второе место, где записано то же правило,
   однажды разойдётся с первым, и разошедшееся будут искать неделю —
   в этом проекте так уже бывало. Поэтому: экран спрашивает, правила
   отвечают. Нельзя спросить — значит новый вопрос надо добавить
   в правила, а не посчитать здесь «по-быстрому».

   Играют двое с одного телефона по очереди. Робота на этом этапе нет
   вовсе. Доска поворачивается к тому, чей ход, — как за настоящим
   столом её просто поворачивают; подписи полей едут вместе с ней.
   Кому поворот мешает (один человек разбирает позицию за обе стороны) —
   выключает кнопкой, и выбор запоминается.

   Как ходят пальцем:
     • тап по своей фигуре — она поднимается, поля для хода
       подсвечиваются (точка — пустое поле, кольцо — взятие);
     • тап по подсвеченному полю — фигура идёт туда;
     • пешка дошла до края — снизу появляется выбор из четырёх фигур,
       и ход делается только после выбора: кем ей стать, решает игрок;
     • тап по самой поднятой фигуре — передумал, выбор сброшен;
     • тап по другой своей фигуре — поднимается она.
   ===================================================================== */

(function () {
  const Правила = window.ШахматыПравила;

  const узелДоски = document.getElementById('доска');
  const строкаХода = document.getElementById('строка-хода');
  const экранИтога = document.getElementById('экран-итога');
  const заголовокИтога = document.getElementById('заголовок-итога');
  const причинаИтога = document.getElementById('причина-итога');
  const экранПревращения = document.getElementById('экран-превращения');
  const кнопкаЗаново = document.getElementById('кнопка-заново');
  const кнопкаЕщё = document.getElementById('кнопка-ещё');
  const кнопкаПоворота = document.getElementById('кнопка-поворот');
  const кнопкаМеток = document.getElementById('кнопка-метки');
  const кнопкаОтменыПревращения = document.getElementById('кнопка-превращение-отмена');
  const кнопкиПревращения = document.querySelectorAll('.кнопка--превращение');

  /* Молчащая страница хуже сломанной: человек тыкает в доску и решает,
     что зависла вся игра. Поэтому о пропавших правилах говорим прямо. */
  if (!Правила) {
    if (строкаХода) строкаХода.textContent = 'Правила не загрузились — обновите страницу';
    console.error('js/шахматы-правила.js не подключился: экрану не у кого спросить про ходы');
    return;
  }

  const БУКВЫ = 'abcdefgh';
  const ПОКАЗ_ОТКАЗА = 900;      // сколько миллисекунд вздрагивает клетка, куда нельзя

  /* ------------------------------------------------------------------
     ЗНАКИ ФИГУР.

     Картинок нет — это правило проекта, и оно тут кстати: восемь
     файлов значков грузились бы дольше всей игры. Берём знаки Юникода.

     Тонкость, из-за которой знаки выбраны именно эти. В Юникоде две
     половины: «белые» (U+2654…) нарисованы контуром, «чёрные»
     (U+265A…) — залитые. Казалось бы, вот и обе стороны. Но контурные
     знаки на светлой клетке почти исчезают, а на части телефонов две
     половины ещё и нарисованы разными шрифтами — тогда белый конь
     и чёрный конь оказываются разной формы и разного размера, и доска
     выглядит как склеенная из двух наборов.

     Поэтому берём ТОЛЬКО залитые знаки — для обеих сторон одни и те же,
     а цвет и ободок задаёт оформление (.фигура--белая / .фигура--чёрная).
     Форма фигуры тогда одинакова у обоих цветов на любом телефоне,
     а различаются они заливкой — ровно как настоящие.

     Хвостик ︎ — это «рисуй как букву, а не как смайлик». Без него
     часть Android рисует пешку цветной картинкой не в масштаб. */
  const ЗНАК_ФИГУРЫ = {
    'король': '♚︎',
    'ферзь':  '♛︎',
    'ладья':  '♜︎',
    'слон':   '♝︎',
    'конь':   '♞︎',
    'пешка':  '♟︎'
  };

  /* ------------------------------------------------------------------
     Что экран помнит про себя. Про партию он не помнит ничего:
     всё, что можно спросить у правил, спрашивается заново.
     ------------------------------------------------------------------ */
  let партия = null;
  let выбранноеПоле = null;     // поле поднятой фигуры или null
  /* Законные ходы поднятой фигуры — прямо те, что дали правила.
     Объекты ходов принадлежат партии, менять их нельзя (так записано
     в самих правилах): мы их только читаем и отдаём обратно. */
  let ходыВыбранной = [];
  /* Пешка дошла до края, и мы ждём, кем ей стать: здесь лежат четыре
     хода на одно и то же поле, по одному на каждую фигуру. */
  let ожидаемПревращение = null;
  /* Откуда и куда сходили прошлым ходом — только чтобы подсветить.
     Держим строками, а не самим ходом: ход принадлежит уже прошлой
     позиции, и после хода его список правила соберут заново. */
  let последнийХод = null;

  let таймерОтказа = null;
  let клеткаОтказа = null;

  const клеткиПоПолю = new Map();   // 'e4' → узел клетки
  /* Куда смотрит доска. Обычно — глазами белых (первая горизонталь снизу). */
  let доскаПеревёрнута = false;

  /* Настройки помним между запусками: ходить за ними после каждого
     обновления страницы неудобно. Ключи свои, шахматные. */
  const КЛЮЧ_ПОВОРОТА = 'шахматы:поворот';
  const КЛЮЧ_МЕТОК = 'шахматы:метки';
  let поворотРазрешён = прочитатьНастройку(КЛЮЧ_ПОВОРОТА) !== 'нет';
  /* Подписи полей в шахматах включены по умолчанию, в отличие от шашек:
     ходы здесь называют буквой и цифрой («конь на f3»), и без подписей
     новичку нечем свериться. */
  let показыватьМетки = прочитатьНастройку(КЛЮЧ_МЕТОК) !== 'нет';

  /* ==================================================================
     ДОСКА: собираем один раз на каждый поворот, дальше только меняем
     классы. Перерисовывать разметку на каждый ход не нужно — от этого
     на телефоне мигает картинка и теряется нажатие. Поворот — другое
     дело: там меняется всё, и собрать клетки заново проще и честнее,
     чем переставлять их по одной.
     ================================================================== */
  function построитьДоску(перевёрнута) {
    доскаПеревёрнута = перевёрнута;
    клеткиПоПолю.clear();
    узелДоски.textContent = '';
    узелДоски.classList.toggle('доска-шахмат--перевёрнута', перевёрнута);

    const куски = document.createDocumentFragment();

    /* Порядок рядов и столбцов — глазами того, кто сидит снизу.
       Белые: сверху восьмая горизонталь, слева столбец a.
       Чёрные: сверху первая, слева столбец h — доска повёрнута
       на полоборота, а не отражена. */
    const ряды = [];
    const столбцы = [];
    for (let i = 0; i < 8; i++) {
      ряды.push(перевёрнута ? i + 1 : 8 - i);
      столбцы.push(перевёрнута ? 7 - i : i);
    }
    // Подписи полей едут вместе с доской: цифры вдоль левого края,
    // буквы вдоль нижнего — какие бы ряд и столбец там ни оказались.
    const левыйСтолбец = столбцы[0];
    const нижнийРяд = ряды[7];

    for (const ряд of ряды) {
      for (const столбец of столбцы) {
        const имя = БУКВЫ[столбец] + ряд;
        const клетка = document.createElement('div');
        /* Цвет клетки считаем здесь, и это не нарушение правила
           «правила спрашиваем у правил»: от цвета поля не зависит
           ни один ход, это рисунок доски, а не её закон. Наружу
           правила про цвет и не говорят. Отсчёт от a1: оно тёмное. */
        const тёмное = (ряд + столбец) % 2 === 1;
        клетка.className = 'поле ' + (тёмное ? 'поле--тёмное' : 'поле--светлое');

        if (столбец === левыйСтолбец) клетка.appendChild(метка('метка-цифра', String(ряд)));
        if (ряд === нижнийРяд) клетка.appendChild(метка('метка-буква', БУКВЫ[столбец]));

        // Имя поля держим и в разметке — так проверке и человеку
        // в инструментах браузера видно, куда он тыкает.
        клетка.setAttribute('data-поле', имя);
        клеткиПоПолю.set(имя, клетка);
        куски.appendChild(клетка);
      }
    }
    узелДоски.appendChild(куски);
  }

  function метка(класс, текст) {
    const узел = document.createElement('span');
    узел.className = класс;
    узел.textContent = текст;
    return узел;
  }

  /**
   * Куда доске смотреть прямо сейчас.
   * После конца партии доску не трогаем: иначе итоговая позиция прыгнула бы
   * перед глазами у того, кто только что поставил мат.
   */
  function доскаДолжнаБытьПеревёрнута() {
    if (!поворотРазрешён) return false;
    if (Правила.партияЗавершена(партия)) return доскаПеревёрнута;
    return Правила.чейХод(партия) === Правила.ЧЁРНЫЕ;
  }

  /* ==================================================================
     ОТРИСОВКА: всё, что видно, собирается из партии и поднятой фигуры.
     ================================================================== */
  function отрисовать() {
    // Очередь перешла к другой стороне — сначала поворачиваем доску к ней
    const надоПеревернуть = доскаДолжнаБытьПеревёрнута();
    if (надоПеревернуть !== доскаПеревёрнута) построитьДоску(надоПеревернуть);

    /* Куда можно пойти поднятой фигурой и будет ли это взятием.
       Список берём у правил целиком: рокировка, взятие на проходе
       и превращение приходят оттуда же и подсвечиваются сами собой. */
    const цели = new Map();
    for (const ход of ходыВыбранной) цели.set(ход.куда, ход.взятие !== null);

    /* Поле короля, которому объявлен шах. Спрашиваем и у законченной
       партии тоже: после мата красная пометка на короле объясняет,
       чем всё кончилось, лучше любой надписи. */
    const полеШаха = Правила.подШахом(партия)
      ? Правила.полеКороля(партия, Правила.чейХод(партия))
      : null;

    клеткиПоПолю.forEach(function (клетка, имя) {
      клетка.classList.toggle('поле--выбрано', имя === выбранноеПоле);
      клетка.classList.toggle('поле--можно', цели.get(имя) === false);
      клетка.classList.toggle('поле--можно-взятие', цели.get(имя) === true);
      клетка.classList.toggle('поле--шах', имя === полеШаха);
      клетка.classList.toggle('поле--последний', последнийХод !== null &&
        (имя === последнийХод.откуда || имя === последнийХод.куда));
      поставитьФигуру(клетка, Правила.фигура(партия, имя));
    });

    строкаХода.textContent = словаОХоде();
    покраситьСтрокуХода();
  }

  /* Знак фигуры в клетке. Меняем только то, что изменилось: лишняя
     запись в textContent заставляет браузер пересчитывать раскладку,
     а клеток 64 и трогаем мы их после каждого хода. */
  function поставитьФигуру(клетка, что) {
    let узел = клетка.querySelector('.фигура');
    if (!что) {
      if (узел) узел.remove();
      return;
    }
    if (!узел) {
      узел = document.createElement('span');
      клетка.appendChild(узел);
    }
    const класс = 'фигура ' + (что.цвет === Правила.БЕЛЫЕ ? 'фигура--белая' : 'фигура--чёрная');
    if (узел.className !== класс) узел.className = класс;
    const знак = ЗНАК_ФИГУРЫ[что.тип];
    if (узел.textContent !== знак) узел.textContent = знак;
  }

  /* Цвет стороны, которая ходит, отдельным классом. Оформителю он нужен,
     потому что CSS не умеет читать надпись: по классу он ставит рядом
     кружок нужного цвета, и чей ход — видно, не вчитываясь. */
  function покраситьСтрокуХода() {
    const идёт = !Правила.партияЗавершена(партия);
    const белые = идёт && Правила.чейХод(партия) === Правила.БЕЛЫЕ;
    строкаХода.classList.toggle('строка-хода--белые', идёт && белые);
    строкаХода.classList.toggle('строка-хода--чёрные', идёт && !белые);
  }

  /** Что написано над доской. Слова наши, а факты — из правил. */
  function словаОХоде() {
    if (Правила.партияЗавершена(партия)) return названиеИтога(Правила.итог(партия));
    if (ожидаемПревращение) return 'Пешка дошла до края — выберите, кем ей стать';
    const чей = Правила.чейХод(партия) === Правила.БЕЛЫЕ ? 'Ходят белые' : 'Ходят чёрные';
    return Правила.подШахом(партия) ? чей + ': королю шах' : чей;
  }

  /* ==================================================================
     ПАЛЕЦ
     ================================================================== */
  function тап(поле) {
    if (Правила.партияЗавершена(партия)) return;
    // Пока не сказано, кем станет пешка, ход не сделан и доска ждёт.
    if (ожидаемПревращение) return;
    // Гасим прошлую красную вспышку сразу: иначе она висит ещё почти
    // секунду поверх уже сделанного хода и выглядит новой жалобой.
    убратьОтказ();

    // Тап по самой поднятой фигуре — передумал.
    if (поле === выбранноеПоле) {
      снятьВыбор();
      отрисовать();
      return;
    }
    // Тап по подсвеченному полю — идём туда.
    if (выбранноеПоле && ходыВыбранной.some(function (х) { return х.куда === поле; })) {
      пойтиНа(поле);
      return;
    }
    // Всё остальное — попытка поднять фигуру на этом поле.
    поднять(поле);
  }

  /** Поднять фигуру: спрашиваем у правил, куда ей можно. */
  function поднять(поле) {
    const ходы = Правила.ходыФигуры(партия, поле);
    if (ходы.length === 0) {
      отказать(поле);
      return;
    }
    выбранноеПоле = поле;
    ходыВыбранной = ходы;
    отрисовать();
  }

  /** Игрок назвал поле, куда идти. */
  function пойтиНа(поле) {
    const варианты = ходыВыбранной.filter(function (х) { return х.куда === поле; });
    /* Больше одного хода на одно и то же поле бывает только у превращения:
       правила дают четыре хода — в ферзя, ладью, слона и коня. Выбор
       фигуры по правилам за игроком, поэтому спрашиваем, а не решаем сами
       (ферзь чаще всего лучший, но не всегда: конём ставят мат). */
    if (варианты.length > 1) {
      спроситьПревращение(варианты);
      return;
    }
    сходить(варианты[0]);
  }

  function сходить(ход) {
    /* Запоминаем поля до хода: сам объект хода принадлежит уже прошлой
       позиции, и держать его после хода нельзя. */
    const откуда = ход.откуда;
    const куда = ход.куда;
    const получилось = Правила.сделатьХод(партия, ход);
    снятьВыбор();
    if (!получилось) {
      // Такого быть не должно: ход взят из списка самих правил.
      console.error('правила не приняли собственный ход', ход);
      строкаХода.textContent = 'Так походить не вышло — начните ход заново';
      отрисовать();
      return;
    }
    последнийХод = { откуда: откуда, куда: куда };
    отрисовать();
    if (Правила.партияЗавершена(партия)) показатьИтог();
  }

  function снятьВыбор() {
    выбранноеПоле = null;
    ходыВыбранной = [];
  }

  /* Так ходить нельзя: клетка коротко вспыхивает, а строка над доской
     объясняет словами. Просто «ничего не произошло» человек читает как
     поломку — особенно когда фигура связана и потому никуда не идёт. */
  function отказать(поле) {
    убратьОтказ();
    const клетка = клеткиПоПолю.get(поле);
    if (клетка) {
      клетка.classList.add('поле--отказ');
      клеткаОтказа = клетка;
    }
    строкаХода.textContent = словаОтказа(поле);
    таймерОтказа = setTimeout(function () {
      убратьОтказ();
      отрисовать();
    }, ПОКАЗ_ОТКАЗА);
  }

  function убратьОтказ() {
    clearTimeout(таймерОтказа);
    таймерОтказа = null;
    if (клеткаОтказа) клеткаОтказа.classList.remove('поле--отказ');
    клеткаОтказа = null;
  }

  /* Почему не вышло — словами. Про шах говорим отдельно: это первое,
     чего не понимает новичок. «Фигура не ходит, потому что тогда моего
     короля побьют» — самая частая причина отказа в шахматах. */
  function словаОтказа(поле) {
    const что = Правила.фигура(партия, поле);
    const шах = Правила.подШахом(партия);
    if (что && что.цвет === Правила.чейХод(партия)) {
      return шах ? 'Королю шах: этой фигурой его не спасти' : 'Этой фигурой ходить некуда';
    }
    if (выбранноеПоле) {
      return шах ? 'Королю шах — так его не спасти' : 'Туда этой фигурой нельзя';
    }
    if (что) return 'Сейчас ход другого игрока';
    return 'Сначала выберите свою фигуру';
  }

  /* ==================================================================
     ПРЕВРАЩЕНИЕ ПЕШКИ

     Плашка появляется ДО хода: по правилам выбор фигуры — часть хода,
     и пока игрок не выбрал, ход не сделан. Поэтому её можно закрыть
     кнопкой «Передумал» — пешка просто останется поднятой.
     ================================================================== */
  function спроситьПревращение(варианты) {
    ожидаемПревращение = варианты;
    const белые = Правила.чейХод(партия) === Правила.БЕЛЫЕ;
    // Знаки на кнопках рисуем цветом того, кто ходит: иначе чёрный
    // игрок выбирает из белых фигур и на секунду теряется.
    for (const кнопка of кнопкиПревращения) {
      const знак = кнопка.querySelector('.знак-фигуры');
      const тип = кнопка.getAttribute('data-фигура');
      if (!знак || !ЗНАК_ФИГУРЫ[тип]) continue;
      знак.textContent = ЗНАК_ФИГУРЫ[тип];
      знак.className = 'знак-фигуры ' + (белые ? 'фигура--белая' : 'фигура--чёрная');
    }
    экранПревращения.classList.add('экран--виден');
    отрисовать();
  }

  function выбратьПревращение(тип) {
    const варианты = ожидаемПревращение || [];
    const ход = варианты.find(function (х) { return х.превращение === тип; });
    закрытьПревращение();
    if (!ход) {
      // Кнопка с неизвестной фигурой — молча ничего не делаем, пешка поднята
      отрисовать();
      return;
    }
    сходить(ход);
  }

  function закрытьПревращение() {
    ожидаемПревращение = null;
    экранПревращения.classList.remove('экран--виден');
  }

  /* ==================================================================
     ИТОГ И НАЧАЛО ЗАНОВО
     ================================================================== */
  function показатьИтог() {
    const результат = Правила.итог(партия);
    заголовокИтога.textContent = названиеИтога(результат);
    // Причину не пересказываем своими словами: её формулируют правила,
    // и пересказ однажды разойдётся с ними. «Мат: чёрным некуда деться»,
    // «Пат: белым нечем ходить, а шаха нет» — это оттуда.
    причинаИтога.textContent = сБольшойБуквы(результат.причина);
    экранИтога.classList.add('экран--виден');
  }

  function названиеИтога(результат) {
    if (результат.ничья) return 'Ничья';
    return результат.победитель === Правила.БЕЛЫЕ ? 'Белые выиграли' : 'Чёрные выиграли';
  }

  function сБольшойБуквы(слова) {
    return слова ? слова[0].toUpperCase() + слова.slice(1) : '';
  }

  /** Новая партия. Страницу при этом не перезагружаем. */
  function начатьЗаново() {
    убратьОтказ();
    закрытьПревращение();
    партия = Правила.создатьПартию();
    снятьВыбор();
    последнийХод = null;
    экранИтога.classList.remove('экран--виден');
    отрисовать();
  }

  /* ==================================================================
     НАСТРОЙКИ
     ================================================================== */
  function показатьМетки() {
    узелДоски.classList.toggle('доска-шахмат--с-метками', показыватьМетки);
    if (кнопкаМеток) кнопкаМеток.textContent = 'Буквы и цифры: ' + (показыватьМетки ? 'да' : 'нет');
  }

  function показатьПоворот() {
    if (кнопкаПоворота) кнопкаПоворота.textContent = 'Поворот доски: ' + (поворотРазрешён ? 'да' : 'нет');
  }

  /* Память браузера для настроек. Запрещена — играем с настройками
     по умолчанию и не падаем. */
  function прочитатьНастройку(ключ) {
    try {
      return window.localStorage.getItem(ключ);
    } catch (ошибка) {
      return null;
    }
  }

  function записатьНастройку(ключ, значение) {
    try {
      window.localStorage.setItem(ключ, значение);
    } catch (ошибка) { /* запрещённая память — не повод ломать игру */ }
  }

  /* ==================================================================
     ПОДКЛЮЧЕНИЕ
     ================================================================== */
  построитьДоску(false);

  /* Слушаем всю доску целиком, а не каждую клетку: обработчик один
     вместо шестидесяти четырёх, и он не теряется ни при перерисовке,
     ни при повороте доски. */
  узелДоски.addEventListener('click', function (событие) {
    const клетка = событие.target.closest('.поле');
    if (!клетка) return;
    const поле = клетка.getAttribute('data-поле');
    if (поле) тап(поле);
  });

  if (кнопкаЗаново) кнопкаЗаново.addEventListener('click', начатьЗаново);
  if (кнопкаЕщё) кнопкаЕщё.addEventListener('click', начатьЗаново);

  if (кнопкаПоворота) {
    кнопкаПоворота.addEventListener('click', function () {
      поворотРазрешён = !поворотРазрешён;
      записатьНастройку(КЛЮЧ_ПОВОРОТА, поворотРазрешён ? 'да' : 'нет');
      показатьПоворот();
      отрисовать();
    });
  }

  if (кнопкаМеток) {
    кнопкаМеток.addEventListener('click', function () {
      показыватьМетки = !показыватьМетки;
      записатьНастройку(КЛЮЧ_МЕТОК, показыватьМетки ? 'да' : 'нет');
      показатьМетки();
    });
  }

  for (const кнопка of кнопкиПревращения) {
    кнопка.addEventListener('click', function () {
      выбратьПревращение(кнопка.getAttribute('data-фигура'));
    });
  }
  if (кнопкаОтменыПревращения) {
    кнопкаОтменыПревращения.addEventListener('click', function () {
      закрытьПревращение();
      отрисовать();   // пешка остаётся поднятой: можно выбрать другое поле
    });
  }

  показатьМетки();     // при загрузке — как человек выбрал в прошлый раз
  показатьПоворот();
  начатьЗаново();
})();
