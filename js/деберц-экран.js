  function живаяКарта(к, родина) {
    const узел = движение.узел(к.id, () => карта(к, true), {
      родина, переворот: родина === эл('колода'), раздача: родина === эл('колода'), долгийЛёт: родина !== эл('колода') && родина !== эл('карты-человека')
    });
    узел.classList.remove('карта--можно', 'карта--нельзя');
    узел.style.removeProperty('left'); узел.style.removeProperty('top');
    узел.style.removeProperty('--номер-в-веере');
    узел.onclick = null; узел.disabled = true;
    return узел;
  }
  function веер(контейнер, сверху) {
    const карты = [...контейнер.children], n = карты.length;
    контейнер.style.setProperty('--карт-в-веере', n);
    if (!n) return;
    const ширина = карты[0].offsetWidth, доступно = контейнер.clientWidth;
    const шаг = n > 1 ? Math.min(ширина * .62, (доступно - ширина - 8) / (n - 1)) : 0;
    const старт = (доступно - ширина - шаг * (n - 1)) / 2;
    карты.forEach((к, i) => { к.style.left = Math.round(старт + шаг * i) + 'px'; к.style.top = сверху + 'px'; к.style.setProperty('--номер-в-веере', i); });
  }
