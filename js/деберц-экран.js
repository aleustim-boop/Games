      const кнопка = эл('экран-комнаты').classList.contains('экран--виден') ? эл('кнопка-комната-отмена')
        : эл('экран-входа').classList.contains('экран--виден') ? эл('кнопка-вход-назад') : эл('кнопка-друг-назад');
