(function () {
  const ПОРОГ_МАЛО = 10;   // на последних десяти секундах отсчёт заметнее
  // Фазы, где ход ждут от одного места и отсчёт стоит в плашке «Ваш ход / Ходит …».
  const ФАЗЫ_ПИЛЮЛИ = ['торговля', 'игра', 'взятка', 'пересдача'];
  // Виды событий комнаты, слова которых экран показывает (признак ставит сервер).
  // «раунд-сам» — просрочка на итоге раздачи: раздачу начал бот, слова «Следующая раздача началась сама».
  // «ход-по-времени-мой» — время вышло у получателя (слова для него сервер уже написал).
  const СЛОВА_ПРО_ВРЕМЯ = ['ход-по-времени', 'ход-по-времени-мой', 'раунд-сам'];
  const числоЧасов = остаток => typeof остаток === 'number' && Number.isFinite(остаток);

  /** Сколько секунд осталось сейчас: присланное минус прошедшее с ответа, округлённое ВВЕРХ
      (как считает сервер). Не ниже нуля и не выше присланного. */
  function секундыСейчас(остаток, получено, сейчас) {
    const прошло = Math.max(0, (сейчас - получено) / 1000);
    return Math.max(0, Math.min(остаток, Math.ceil(остаток - прошло)));
  }
  const пилюляХода = вход => {
    const секунд = секундыСейчас(вход.остаток, вход.получено, вход.сейчас);
    // Между числом и «с» неразрывный пробел: «с» не уезжает на другую строку.
    return { секунд, мало: секунд <= ПОРОГ_МАЛО, укого: вход.ход === 0 ? 'я' : 'сосед', текст: секунд + ' с' };
  };
  /* Пилюля в плашке: только за столом по сети и только пока часы идут (вдвоём и
     на конце партии остаток — null, отсчёта нет совсем). */
  function отсчёт(вход) {
    if (!вход || !вход.поСети || !числоЧасов(вход.остаток) || !ФАЗЫ_ПИЛЮЛИ.includes(вход.фаза)) return null;
    return пилюляХода(вход);
  }
  /* На итоге раздачи плашку закрывает окно результата, поэтому отсчёт — строкой в самом окне. */
  function отсчётИтога(вход) {
    if (!вход || !вход.поСети || !числоЧасов(вход.остаток) || вход.фаза !== 'итог') return null;
    const п = пилюляХода(вход);
    return { секунд: п.секунд, мало: п.мало, текст: 'Следующая сдача начнётся через ' + п.секунд + ' с' };
  }
  /* Слова события комнаты берём ТОЛЬКО про время: комната дописывает к событиям слова голосования.
     Отличаем по виду события, который собирает сервер, а не по тексту. */
  function словаПроВремя(видСобытия, событие) {
    return СЛОВА_ПРО_ВРЕМЯ.includes(видСобытия) && typeof событие === 'string' ? событие : '';
  }
  /* Время вышло у меня самого: признак ставит сервер (server/игры/деберц.js, видДляИгрока);
     экран показывает слова и тогда, когда ход снова мой. */
  function мойХодПоВремени(видСобытия) {
    return видСобытия === 'ход-по-времени-мой';
  }
  function чтоНарисовать(вход) {
    if (!вход || !вход.поСети) return { пилюля: null, строкаИтога: null, слова: '' };
    return { пилюля: отсчёт(вход), строкаИтога: отсчётИтога(вход), слова: словаПроВремя(вход.видСобытия, вход.событие) };
  }
  /* Спит ли место с этим номером (поле «застолом» из вида): пометка только у спящего, ключа у остальных нет. */
  function спитЛиМесто(застолом, номерМеста) {
    return Array.isArray(застолом) && застолом.some(м => м && м.номер === номерМеста && м.спит === true);
  }

  const api = { секундыСейчас, отсчёт, отсчётИтога, словаПроВремя, чтоНарисовать, спитЛиМесто, мойХодПоВремени, ПОРОГ_МАЛО };
  if (typeof module !== 'undefined' && module.exports) module.exports.ДеберцОтсчёт = api;
  if (typeof window !== 'undefined') window.ДеберцОтсчёт = api;
})();
