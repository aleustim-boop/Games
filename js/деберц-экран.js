  function подсказкаОтвета() {
    const первая = игра.стол[0]?.карта;
    if (!первая) return 'Ваш ход. Выберите карту';
    const вМасть = игра.руки[0].filter(к => к.масть === первая.масть);
    if (вМасть.length) {
      const лидер = П.старшаяКарта(игра);
      return первая.масть === игра.козырь && !(игра.парами && лидер.игрок % 2 === 0)
        && вМасть.some(к => П.бьёт(к, лидер.карта, игра.козырь))
        ? 'Ответьте старшим козырем ' + игра.козырь : 'Ответьте в масть ' + первая.масть;
    }
    return игра.руки[0].some(к => к.масть === игра.козырь)
      ? 'Нет ' + первая.масть + ' — ходите козырем ' + игра.козырь : 'Нет масти и козырей — можно любую карту';
  }
