  function этоСловарь(значение) {
    return !!значение && typeof значение === 'object' && !Array.isArray(значение);
  }

  function отказ(причина) {
    return { принято: false, причина: причина };
  }

  // Сколько поставлено в каждую область: {номер: войск}. Ключи после JSON — строки, берём числом.
  function поставленоПоОбластям(черновик) {
    const итог = {};
    const расстановка = (черновик && черновик.расстановка) || {};
    Object.keys(расстановка).forEach(function (к) { итог[Number(к)] = расстановка[к]; });
    return итог;
  }

  // Проверка черновика целиком. Черновик и партию не меняет; отдаёт { принято, причина }.
  function проверитьЧерновик(партия, ключ, черновик) {
    const карта = картаПартии(партия);
    const всего = карта.области.length;
    const хозяева = партия.хозяева;
    function своя(н) {
      return Number.isInteger(н) && н >= 1 && н <= всего && хозяева[н] === ключ;
    }

    if (!этоСловарь(черновик)) return отказ('Черновик не читается');
    const расстановка = черновик.расстановка === undefined ? {} : черновик.расстановка;
    const приказы = черновик.приказы === undefined ? [] : черновик.приказы;
    if (!этоСловарь(расстановка) || !Array.isArray(приказы)) return отказ('Черновик не читается');

    // Расстановка: только на свои, целыми числами, не больше подкрепления.
    let поставлено = 0;
    const ключи = Object.keys(расстановка);
    for (let и = 0; и < ключи.length; и++) {
      const сколько = расстановка[ключи[и]];
      if (!своя(Number(ключи[и]))) return отказ('Ставить войска можно только на свои области');
      if (!Number.isInteger(сколько) || сколько < 0) return отказ('Ставить можно только целое число войск');
      поставлено += сколько;
    }
    const можноПоставить = партия.подкрепление[ключ] || 0;
    if (поставлено > можноПоставить) return отказ('Поставить можно не больше ' + можноПоставить);

    // Приказы: из своей в соседнюю, хотя бы одно войско, одна пара — один приказ.
    const пары = {};
    for (let и = 0; и < приказы.length; и++) {
      const п = приказы[и];
      if (!этоСловарь(п) || !Number.isInteger(п.из) || !Number.isInteger(п.в) || !Number.isInteger(п.сколько)) {
        return отказ('Приказ не читается');
      }
      if (!своя(п.из)) return отказ('Приказ можно отдать только из своей области');
      if (п.в === п.из || !соседниеОбласти(карта, п.из, п.в)) return отказ('Ходить можно только в соседнюю область');
      if (п.сколько < 1) return отказ('В приказе нужно хотя бы одно войско');
      const пара = п.из + '-' + п.в;
      if (пары[пара]) return отказ('В одну область из одной — только один приказ');
      пары[пара] = true;
    }

    // В каждой области остаётся хотя бы 1: из A не больше «войска + поставлено − 1».
    const поставленоВ = поставленоПоОбластям({ расстановка: расстановка });
    const отправлено = {};
    for (let и = 0; и < приказы.length; и++) {
      const из = приказы[и].из;
      отправлено[из] = (отправлено[из] || 0) + приказы[и].сколько;
      const можно = партия.войска[из] + (поставленоВ[из] || 0) - ЧИСЛА.остаётсяВОбласти;
      if (отправлено[из] > можно) return отказ(изОбласти(карта, из) + ' можно отправить не больше ' + Math.max(0, можно));
    }
    return { принято: true, причина: null };
  }

  // Куда ставится остаток подкрепления (ТЗ 3.3): в свою столицу, если она у игрока;
  // иначе в самую большую свою область (войска на начало раунда + поставленное), равенство — меньший номер.
  // Отдаёт { область, столица } или null, если областей нет.
  function кудаОстаток(партия, ключ, черновик) {
    const хозяева = партия.хозяева;
    const своя = партия.столицы.find(function (с) {
      return с.хозяинНаСтарте === ключ && хозяева[с.область] === ключ;
    });
    if (своя) return { область: своя.область, столица: true };
    const поставленоВ = поставленоПоОбластям(черновик);
    let лучшая = null;
    let лучшеВойск = -1;
    номераОбластей(картаПартии(партия)).forEach(function (н) {
      if (хозяева[н] !== ключ) return;
      const войск = партия.войска[н] + (поставленоВ[н] || 0);
      if (войск > лучшеВойск) {
        лучшая = н;
        лучшеВойск = войск;
      }
    });
    return лучшая === null ? null : { область: лучшая, столица: false };
  }

  // Время вышло, «Готово» не нажато: черновик идёт в дело как есть, остаток ставится без вопроса.
  // Отдаёт новый черновик; присланный не меняет.
  function остатокПоПросрочке(партия, ключ, черновик) {
    const итог = {
      расстановка: Object.assign({}, (черновик && черновик.расстановка) || {}),
      приказы: ((черновик && черновик.приказы) || []).map(function (п) { return Object.assign({}, п); })
    };
    const поставлено = Object.keys(итог.расстановка).reduce(function (сумма, к) {
      return сумма + итог.расстановка[к];
    }, 0);
    const остаток = (партия.подкрепление[ключ] || 0) - поставлено;
    if (остаток <= 0) return итог;
    const куда = кудаОстаток(партия, ключ, итог);
    if (!куда) return итог;
    итог.расстановка[куда.область] = (итог.расстановка[куда.область] || 0) + остаток;
    return итог;
  }

