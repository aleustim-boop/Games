    картаПартии: картаПартии,
    новаяПартия: новаяПартия,
    подкрепление: подкрепление,
    пустойЧерновик: пустойЧерновик,
    проверитьЧерновик: проверитьЧерновик,
    видПриказа: видПриказа,
    шанс: шанс,
    процентШанса: процентШанса,
    ожидаемыеПотери: ожидаемыеПотери,
    нужноПри: нужноПри,
    кудаОстаток: кудаОстаток,
    остатокПоПросрочке: остатокПоПросрочке,
