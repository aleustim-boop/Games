  function узел(id) { return document.getElementById(id); }

  /* ---------- Сборка узлов из описания ---------- */

  /**
   * Узел по описанию: э(тег, { id, класс, текст, значок, атрибуты }, ...дети).
   * Узел с id, который на странице уже есть, не создаётся (вернёт null) —
   * двух узлов с одним id быть не должно, а старый уже с обработчиками.
   */
  function э(тег, свойства) {
    const с = свойства || {};
    if (с.id && узел(с.id)) return null;
    const у = document.createElement(тег);
    if (с.id) у.id = с.id;
    if (с.класс) у.className = с.класс;
    const атрибуты = с.атрибуты || {};
    Object.keys(атрибуты).forEach(function (имя) { у.setAttribute(имя, атрибуты[имя]); });
    if (с.текст !== undefined) у.textContent = с.текст;
    if (с.значок) у.innerHTML = с.значок;
    for (let i = 2; i < arguments.length; i++) {
      if (arguments[i]) у.appendChild(arguments[i]);
    }
    return у;
  }

  /** Пустая метка «место-…»: сюда js/дурак-комната.js переставляет настоящий узел. */
  function метка(id) {
    return э('span', { id: 'место-' + id, класс: 'скрыт', атрибуты: { 'aria-hidden': 'true' } });
  }

