/* =====================================================================
   Мои друзья: список тех, кто согласился дружить, входящие заявки
   и способ добавить нового друга.

   Друзья — не то же самое, что «знакомые» (server/знакомые.js, с кем
   играли — забывается через 60 дней, без подтверждения). Дружба —
   список, который человек собрал сам, бессрочный, и стать другом
   можно только взаимно (server/друзья.js). Добавить можно только
   того, с кем уже играли — владелец решил так нарочно, чтобы не
   заводить свой код/перебор (штаб/план-друзья-список.md, «Решения
   владельца» 20.09): список «с кем играл» уже есть, дверь /знакомые,
   и на нём просто появляется кнопка «Добавить в друзья».

   Две двери наружу:
       window.ЭкранДрузей.открыть()         // список друзей и заявок
       window.ЭкранДрузей.открытьДобавление() // список «с кем играл» + кнопка

   Входа на первый экран нигде в разметке пока нет — его подключит
   отдельный этап (фильтр «Друзья» на экране рейтинга, ссылка «Добавить
   друга» у пустого среза). До тех пор экран открывается только этой
   дверью — например, из консоли или будущим кодом.

   Главное правило файла — то же, что у js/рейтинг-экран.js: ВСЁ,
   ЧТО ПРИШЛО С СЕРВЕРА, ВСТАВЛЯЕТСЯ ТЕКСТОМ (createElement + textContent,
   ни одного innerHTML). Имена в списке пишут живые люди.
   ===================================================================== */

'use strict';

(function () {

  const ЭКРАН = 'экран-друзей';
  const ЭКРАН_ДОБАВИТЬ = 'экран-добавить-друга';

  /* Сколько ждём ответ сервера — тот же запас, что у рейтинга: партия
     не идёт, спешить некуда, но и держать человека перед пустым
     списком полминуты нельзя. */
  const ЖДЁМ_ОТВЕТ = 8000;

  /* Откуда открыли «Мои друзья» — чтобы «Назад» вернул туда, а не всегда
     в меню. У «Добавить друга» своя память не нужна: на него можно
     попасть только отсюда же, и «Назад» с него всегда ведёт на «Мои
     друзья». */
  let откудаПришли = 'экран-меню';

  /* Поколение запроса списка друзей. Пока грузится один список, человек
     может успеть закрыть экран и открыть его снова — тогда устаревший
     ответ не должен нарисоваться поверх нового. */
  let поколениеСписка = 0;

  /* -------------------------------------------------------------------
     Разговор с сервером — тот же приём, что в js/рейтинг-экран.js:
     свой адрес и подпись, потому что сеть.js этих дверей не знает
     (друзья — отдельная сущность, свои маршруты /друзья-*).
     ------------------------------------------------------------------- */

  /** Адрес сервера — спрашиваем js/сеть.js, он один знает верный. */
  function адресСервера() {
    try {
      if (window.Сеть && typeof window.Сеть.адрес === 'function') {
        return String(window.Сеть.адрес() || '');
      }
    } catch (сбой) {
      /* сеть.js есть, но споткнулся — адреса не будет, скажем честно ниже */
    }
    return '';
  }

  /** Подпись Telegram — только по ней сервер узнаёт, кто спрашивает. */
  function подписьTelegram() {
    try {
      const приложение = window.Telegram && window.Telegram.WebApp;
      return (приложение && приложение.initData) || '';
    } catch (сбой) {
      return '';
    }
  }

  /** Что не так с адресом — короткое слово-повод или null. */
  function бедаАдреса(адрес) {
    if (!String(адрес || '').trim()) return 'нет-адреса';
    if (!/^https?:\/\//i.test(адрес)) return 'плохой-адрес';
    return null;
  }

  /**
   * Сходить в одну из дверей /друзья-*. Обещание никогда не срывается:
   * любая беда возвращается обычным ответом с пометкой, разбирает её
   * вызывающий код в одном месте.
   */
  function сходить(дверь, тело) {
    const адрес = адресСервера();
    const беда = бедаАдреса(адрес);
    if (беда) return Promise.resolve({ беда: беда, данные: null });

    const управление = typeof AbortController !== 'undefined' ? new AbortController() : null;
    const сторож = setTimeout(function () {
      if (управление) управление.abort();
    }, ЖДЁМ_ОТВЕТ);

    const настройки = {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'bypass-tunnel-reminder': 'true'
      },
      body: JSON.stringify(Object.assign({ initData: подписьTelegram() }, тело || {}))
    };
    if (управление) настройки.signal = управление.signal;

    return fetch(адрес + дверь, настройки)
      .then(function (ответ) {
        return ответ.json().then(
          function (данные) {
            if (!данные || typeof данные !== 'object') return { беда: 'связь', данные: null };
            return { беда: null, данные: данные };
          },
          function () { return { беда: 'связь', данные: null }; }
        );
      })
      .catch(function () {
        return { беда: 'связь', данные: null };
      })
      .then(function (итог) {
        clearTimeout(сторож);
        return итог;
      });
  }

  /** Фраза для человека по беде адреса/связи — тот же тон, что у рейтинга. */
  function фразаБеды(беда) {
    if (беда === 'нет-адреса') return 'Игра не знает адреса сервера — список друзей недоступен.';
    if (беда === 'плохой-адрес') return 'Адрес сервера настроен неверно — список друзей недоступен.';
    return 'Сервер сейчас не отвечает. Попробуйте открыть список друзей позже.';
  }

  /* -------------------------------------------------------------------
     Разбор ответа /друзья-список: только этой части файл можно
     прогнать в Node без браузера — она страницу не трогает.
     ------------------------------------------------------------------- */

  /** Привести одну запись { ключ, имя } к безопасному виду. */
  function чистаяЗапись(сырая) {
    const запись = (сырая && typeof сырая === 'object') ? сырая : {};
    return {
      ключ: typeof запись.ключ === 'string' ? запись.ключ : '',
      имя: typeof запись.имя === 'string' && запись.имя.trim() ? запись.имя.trim() : 'Без имени'
    };
  }

  /**
   * Что показать по ответу /друзья-список. Не трогает страницу —
   * решает только форму, рисование делает отдельная функция.
   *
   * Возвращает: { беда: текст|null, друзья: [...], входящие: [...] }
   * «беда» — готовая фраза, когда список показать нельзя вовсе
   * (сервер не ответил, не узнал человека).
   */
  function видСписковДрузей(итог) {
    if (итог.беда) return { беда: фразаБеды(итог.беда), друзья: [], входящие: [] };
    const данные = итог.данные || {};
    if (данные.узналиВас !== true) {
      return {
        беда: 'Игра открыта не в Telegram, поэтому список друзей недоступен.',
        друзья: [],
        входящие: []
      };
    }
    return {
      беда: null,
      друзья: (Array.isArray(данные.друзья) ? данные.друзья : []).map(чистаяЗапись),
      входящие: (Array.isArray(данные.входящие) ? данные.входящие : []).map(чистаяЗапись)
    };
  }

  /* -------------------------------------------------------------------
     Рисование: узлы, строки, списки
     ------------------------------------------------------------------- */

  function узел(id) {
    return document.getElementById(id);
  }

  function очистить(эл) {
    if (!эл) return;
    while (эл.firstChild) эл.removeChild(эл.firstChild);
  }

  /** Показать/спрятать узел классом «скрыт» — тот же приём, что везде в игре. */
  function показать(эл, видно) {
    if (эл) эл.classList.toggle('скрыт', !видно);
  }

  function текстом(эл, текст) {
    if (эл) эл.textContent = текст || '';
  }

  /** Мелкая кнопка действия строки — общий класс, вид не придумываем свой. */
  function кнопкаДействия(подпись, действие) {
    const кнопка = document.createElement('button');
    кнопка.type = 'button';
    кнопка.className = 'кнопка кнопка--мелкая';
    кнопка.textContent = подпись;
    if (действие) кнопка.addEventListener('click', действие);
    return кнопка;
  }

  /**
   * Одна строка списка — тот же трёхколоночный вид, что у «знакомых»
   * в комнате (js/дурак-комната.js, класс «.знакомые .таблица__строка»):
   * узкая метка · имя · действия. Действия — отдельным, третьим ребёнком
   * строки (а не вложены в ячейку имени), поэтому в специальной раздвижке
   * под кнопку-оверлей нужды нет — обычный грид сам отводит им место.
   */
  function строкаЧеловека(имя, кнопки) {
    const строка = document.createElement('div');
    строка.className = 'таблица__строка знакомые__строка';
    const метка = document.createElement('span');
    метка.className = 'таблица__место знакомые__метка';
    const имяЭл = document.createElement('span');
    имяЭл.className = 'таблица__очки знакомые__имя';
    имяЭл.textContent = имя;
    const действия = document.createElement('span');
    кнопки.forEach(function (кнопка) { действия.appendChild(кнопка); });
    строка.appendChild(метка);
    строка.appendChild(имяЭл);
    строка.appendChild(действия);
    return строка;
  }

  /* ---------- Экран «Мои друзья» ---------- */

  /** Удалить друга — с переспросом: первое нажатие только «Точно?». */
  function привязатьУдаление(кнопка, друг) {
    кнопка.addEventListener('click', function () {
      if (кнопка.disabled) return;
      if (!кнопка.dataset.подтверждение) {
        кнопка.dataset.подтверждение = '1';
        кнопка.textContent = 'Точно?';
        return;
      }
      кнопка.disabled = true;
      кнопка.textContent = 'Удаляем…';
      сходить('/друзья-удалить', { ключ: друг.ключ }).then(function (итог) {
        if (итог.беда || !итог.данные || итог.данные.ок !== true) {
          кнопка.disabled = false;
          delete кнопка.dataset.подтверждение;
          кнопка.textContent = 'Удалить';
          текстом(узел('друзья-беда'),
            (итог.данные && итог.данные.причина) || 'Удалить не вышло — попробуйте ещё раз.');
          показать(узел('друзья-беда'), true);
          return;
        }
        загрузитьДрузей();
      });
    });
  }

  function привязатьПринятьОтклонить(кнопкаПринять, кнопкаОтклонить, заявка) {
    function отправить(дверь, кнопкаНажатая) {
      кнопкаПринять.disabled = true;
      кнопкаОтклонить.disabled = true;
      кнопкаНажатая.textContent = дверь === '/друзья-принять' ? 'Принимаем…' : 'Отклоняем…';
      сходить(дверь, { ключ: заявка.ключ }).then(function (итог) {
        if (итог.беда || !итог.данные || итог.данные.ок !== true) {
          кнопкаПринять.disabled = false;
          кнопкаОтклонить.disabled = false;
          кнопкаНажатая.textContent = дверь === '/друзья-принять' ? 'Принять' : 'Отклонить';
          текстом(узел('друзья-беда'),
            (итог.данные && итог.данные.причина) || 'Не вышло — попробуйте ещё раз.');
          показать(узел('друзья-беда'), true);
          return;
        }
        загрузитьДрузей();
      });
    }
    кнопкаПринять.addEventListener('click', function () { отправить('/друзья-принять', кнопкаПринять); });
    кнопкаОтклонить.addEventListener('click', function () { отправить('/друзья-отклонить', кнопкаОтклонить); });
  }

  function строкаДруга(друг) {
    const кнопкаУдалить = кнопкаДействия('Удалить', null);
    привязатьУдаление(кнопкаУдалить, друг);
    return строкаЧеловека(друг.имя, [кнопкаУдалить]);
  }

  function строкаЗаявки(заявка) {
    const кнопкаПринять = кнопкаДействия('Принять', null);
    const кнопкаОтклонить = кнопкаДействия('Отклонить', null);
    привязатьПринятьОтклонить(кнопкаПринять, кнопкаОтклонить, заявка);
    return строкаЧеловека(заявка.имя, [кнопкаПринять, кнопкаОтклонить]);
  }

  /** Нарисовать «Мои друзья» по готовому решению видСписковДрузей. */
  function нарисоватьДрузей(вид) {
    текстом(узел('друзья-беда'), вид.беда || '');
    показать(узел('друзья-беда'), Boolean(вид.беда));

    const блокЗаявок = узел('друзья-заявки-блок');
    const списокЗаявок = узел('друзья-заявки-список');
    очистить(списокЗаявок);
    if (вид.входящие.length) {
      вид.входящие.forEach(function (заявка) { списокЗаявок.appendChild(строкаЗаявки(заявка)); });
      показать(блокЗаявок, true);
    } else {
      показать(блокЗаявок, false);
    }

    const списокДрузей = узел('друзья-список');
    очистить(списокДрузей);
    вид.друзья.forEach(function (друг) { списокДрузей.appendChild(строкаДруга(друг)); });
    показать(узел('друзья-пусто'), !вид.беда && вид.друзья.length === 0);
  }

  /** Спросить сервер и нарисовать список друзей заново. */
  function загрузитьДрузей() {
    const моёПоколение = ++поколениеСписка;
    текстом(узел('друзья-беда'), '');
    показать(узел('друзья-беда'), false);
    сходить('/друзья-список', {}).then(function (итог) {
      if (моёПоколение !== поколениеСписка) return;   // экран уже закрыли/открыли снова
      нарисоватьДрузей(видСписковДрузей(итог));
    });
  }

  /* ---------- Экран «Добавить друга» ---------- */

  /** Пустая плашка — тот же вид, что у «знакомых» в комнате. */
  function плашкаПусто(текст) {
    const п = document.createElement('p');
    п.className = 'таблица__пусто';
    п.textContent = текст;
    return п;
  }

  /** Нажали «Добавить в друзья» у знакомого. */
  function добавитьЗнакомогоВДрузья(знакомый, кнопка) {
    if (кнопка.disabled) return;
    кнопка.disabled = true;
    кнопка.textContent = 'Отправляем…';
    сходить('/друзья-позвать', { ключ: знакомый.ключ }).then(function (итог) {
      if (итог.беда || !итог.данные || итог.данные.ок !== true) {
        кнопка.disabled = false;
        кнопка.textContent = 'Добавить в друзья';
        return;
      }
      кнопка.textContent = итог.данные.статус === 'друзья' ? 'Уже друзья' : 'Заявка отправлена';
    });
  }

  /** Причина, что список «с кем играл» не свежий, — под строками; тот же
      класс и тот же приём, что причинаЗнакомых() в js/дурак-комната.js. */
  function причинаСписка(текст) {
    const п = document.createElement('p');
    п.className = 'подпись знакомые__причина';
    п.textContent = текст;
    return п;
  }

  /** Строка знакомого — тот же вид, что в js/дурак-комната.js (строкаЗнакомого),
      только кнопка «Добавить в друзья» вместо «Позвать», отдельным ребёнком
      строки, а не поверх имени. */
  function строкаЗнакомогоДляДобавления(друг) {
    const заСтолом = друг.сейчасИграет === true;
    const строка = document.createElement('div');
    строка.className = 'таблица__строка знакомые__строка' + (заСтолом ? ' знакомые__строка--за-столом' : '');
    const метка = document.createElement('span');
    метка.className = 'таблица__место знакомые__метка';
    метка.textContent = заСтолом ? '•' : '';
    const имя = document.createElement('span');
    имя.className = 'таблица__очки знакомые__имя';
    имя.textContent = друг.имя || 'Без имени';
    const действия = document.createElement('span');
    // Ключа может не быть только у совсем старого ответа из памяти браузера —
    // тогда звать некого, кнопку не показываем вовсе, а не вешаем на пустоту.
    if (друг.ключ) {
      const кнопка = кнопкаДействия('Добавить в друзья', null);
      кнопка.addEventListener('click', function () { добавитьЗнакомогоВДрузья(друг, кнопка); });
      действия.appendChild(кнопка);
    }
    строка.appendChild(метка);
    строка.appendChild(имя);
    строка.appendChild(действия);
    return строка;
  }

  /** Спросить и нарисовать список «с кем играл» с кнопкой добавления. */
  function загрузитьДляДобавления() {
    const список = узел('добавить-друга-список');
    const пусто = узел('добавить-друга-пусто');
    очистить(список);
    список.appendChild(плашкаПусто('Минутку…'));
    показать(пусто, false);

    if (!window.Сеть || typeof window.Сеть.списокЗнакомых !== 'function') {
      очистить(список);
      текстом(пусто, 'Список «с кем играл» сейчас недоступен.');
      показать(пусто, true);
      return;
    }

    /* window.Сеть.списокЗнакомых() — по договору js/сеть.js (см. сеть.js:5294-5299)
       никогда не отклоняет обещание: любая беда связи приходит через resolve,
       свежий:false и словами в причине. Второго колбэка (на отказ) тут нарочно
       нет — он был бы мёртвым кодом, который никогда не выполнится (нашёл
       ревьюер). */
    window.Сеть.списокЗнакомых().then(function (ответ) {
      очистить(список);
      const старая = список.parentNode && список.parentNode.querySelector('.знакомые__причина');
      if (старая) старая.remove();

      const знакомые = (ответ && Array.isArray(ответ.знакомые) ? ответ.знакомые : []).slice();
      const свежий = Boolean(ответ && ответ.свежий === true);
      const причина = (ответ && ответ.причина) ||
        'Сервер не ответил — список «с кем играл» может быть неполным.';

      if (!знакомые.length) {
        /* Пусто по-честному — только когда список СВЕЖИЙ. Иначе это не
           «не с кем», а беда связи, и молчать о ней или гадать вместо
           сервера нельзя: человек решит, что играть было не с кем. */
        текстом(пусто, свежий
          ? 'Пока не с кем — добавить в друзья можно только тех, с кем уже играли.'
          : причина);
        показать(пусто, true);
        return;
      }
      показать(пусто, false);
      знакомые.forEach(function (друг) { список.appendChild(строкаЗнакомогоДляДобавления(друг)); });
      // Список не пуст, но не свежий (ответ из памяти) — предупреждаем отдельной строкой,
      // не пряча уже показанных знакомых.
      if (!свежий && список.parentNode) список.parentNode.appendChild(причинаСписка(причина));
    });
  }

  /* -------------------------------------------------------------------
     Переключение экранов — тот же приём, что в js/рейтинг-экран.js.
     ------------------------------------------------------------------- */

  function показатьЭкран(id) {
    if (window.ИграПоСети && typeof window.ИграПоСети.экран === 'function') {
      window.ИграПоСети.экран(id);
      return;
    }
    for (const экран of document.querySelectorAll('.экран')) {
      экран.classList.toggle('экран--виден', экран.id === id);
    }
  }

  function текущийЭкран() {
    const открытый = document.querySelector('.экран.экран--виден');
    return (открытый && открытый.id) || 'экран-меню';
  }

  /** Системная стрелка Telegram — тот же приём, что у рейтинга. */
  function попытатьсяПривязатьСтрелку(действие) {
    try {
      if (window.Телеграм && typeof window.Телеграм.показатьСтрелку === 'function') {
        window.Телеграм.показатьСтрелку(действие);
      }
    } catch (сбой) {
      /* нет Telegram — на экране есть обычная кнопка «Назад» */
    }
  }

  function вернутьПрежнююСтрелку() {
    try {
      if (window.Телеграм && typeof window.Телеграм.вернутьПрежнююСтрелку === 'function') {
        window.Телеграм.вернутьПрежнююСтрелку();
      }
    } catch (сбой) { /* нет двери — не страшно */ }
  }

  /**
   * Запомнить экран возврата в ОБЩЕЙ памяти game.js — той самой, которую
   * читает window.вернутьсяОткудаПришли (её слушает и системная стрелка
   * Telegram). Тот же приём, что у открытьРейтингИгроков() в game.js
   * (game.js:10952-10960): «let» и «function» верхнего уровня обычного
   * <script>, не модуля, общие для ВСЕХ таких тегов страницы — game.js
   * грузится раньше нас, и его экранОткудаПришли/запомнитьГдеБыли видны
   * здесь просто по имени, без window.
   *
   * Найдено ревьюером: раньше эта память не трогалась вовсе, и назадИзДрузей()
   * (через window.вернутьсяОткудаПришли) всегда возвращал бы туда, откуда
   * был открыт ПРЕДЫДУЩИЙ служебный экран (например, сам рейтинг), а не
   * туда, откуда открыли «Мои друзья». Сейчас входа на экран в разметке
   * нет, поэтому баг не проявляется — но проявится на этапе, который
   * поведёт на «Мои друзья» с экрана рейтинга.
   *
   * Не трогаем память, когда идём МЕЖДУ своими же двумя экранами (иначе
   * «Назад» после «Добавить друга» зациклился бы сам на себя): «было»
   * передаёт вызывающая сторона.
   */
  function запомнитьМестоВозврата(было) {
    if (было === ЭКРАН || было === ЭКРАН_ДОБАВИТЬ) return;
    try {
      if (typeof запомнитьГдеБыли === 'function') {
        экранОткудаПришли = запомнитьГдеБыли();
      }
    } catch (сбой) {
      /* game.js почему-то не подключился (например, изолированная проверка) —
         довольствуемся локальной памятью ниже. */
    }
  }

  function назадИзДрузей() {
    if (typeof window.вернутьсяОткудаПришли === 'function') {
      window.вернутьсяОткудаПришли();
      return;
    }
    показатьЭкран(откудаПришли);
    вернутьПрежнююСтрелку();
  }

  function назадИзДобавления() {
    показатьЭкран(ЭКРАН);
    попытатьсяПривязатьСтрелку(назадИзДрузей);
  }

  /** Открыть «Мои друзья». */
  function открыть() {
    const было = текущийЭкран();
    if (было !== ЭКРАН && было !== ЭКРАН_ДОБАВИТЬ) откудаПришли = было;
    запомнитьМестоВозврата(было);
    показатьЭкран(ЭКРАН);
    попытатьсяПривязатьСтрелку(назадИзДрузей);
    загрузитьДрузей();
  }

  /** Открыть «Добавить друга» — только с «Моих друзей». */
  function открытьДобавление() {
    запомнитьМестоВозврата(текущийЭкран());
    показатьЭкран(ЭКРАН_ДОБАВИТЬ);
    попытатьсяПривязатьСтрелку(назадИзДобавления);
    загрузитьДляДобавления();
  }

  function нажатие(id, что) {
    const кнопка = узел(id);
    if (кнопка) кнопка.addEventListener('click', что);
  }

  function подключить() {
    нажатие('кнопка-друзья-назад', назадИзДрузей);
    нажатие('кнопка-добавить-друга', открытьДобавление);
    нажатие('кнопка-добавить-друга-назад', назадИзДобавления);
  }

  if (typeof document !== 'undefined') {
    подключить();
    window.ЭкранДрузей = { открыть: открыть, открытьДобавление: открытьДобавление };
  }

  /* Наружу для проверки в Node — только часть, что решает, ЧТО показывать. */
  if (typeof module !== 'undefined' && module.exports) {
    module.exports = { видСписковДрузей: видСписковДрузей };
  }

})();
