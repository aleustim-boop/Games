'use strict';

/* =====================================================================
   ШАШКИ — ЭКРАН «КАК ИГРАТЬ».

   Сам текст правил лежит в шашки.html: это слова для человека, а не код,
   и править их удобнее там, где они видны целиком. Здесь только открыть
   и закрыть экран.

   ГЛАВНОЕ ПРАВИЛО: экран правил ничего не делает с партией. Человек
   открыл его посреди игры, дочитал, нажал «Назад» — и доска ровно та,
   что была: та же позиция, та же очередь хода, тот же поднятый выбор.
   Поэтому здесь нет ни одного обращения к правилам игры или к доске —
   только показать одну секцию и спрятать другую.

   Плашка итога прячется на время чтения и возвращается после — тем же
   способом, что у экрана рекордов, и по той же причине: она лежит
   поверх всего и накрыла бы кнопку «Назад к доске».

   Наружу: window.ШашкиКакИграть = { показать, спрятать, открыты }.
   Стрелка «Назад» Telegram спрашивает «открыты()» и закрывает правила
   первым нажатием — см. js/шашки-телеграм.js.
   ===================================================================== */

(function () {
  var экранПравил = document.getElementById('экран-правил');
  var экранДоски = document.getElementById('экран-шашек');
  var экранИтога = document.getElementById('экран-итога');
  var кнопкаОткрыть = document.getElementById('кнопка-как-играть');
  var кнопкаНазад = document.getElementById('кнопка-правила-назад');

  var плашкаИтогаБылаВидна = false;

  function открыты() {
    return !!(экранПравил && экранПравил.classList.contains('экран--виден'));
  }

  /* Плашку итога прячем и возвращаем через одну общую дверь
     (window.ШашкиЭкран). Своей копии здесь нет нарочно: вместе с плашкой
     прячется и возвращается ряд кнопок под доской, и копия однажды
     забыла бы про них — беда вернулась бы молча. Двери может не быть,
     если файл доски не загрузился: тогда работаем как раньше. */
  function дверьЭкрана() {
    return window.ШашкиЭкран || null;
  }

  function плашкаИтогаВидна() {
    var дверь = дверьЭкрана();
    if (дверь && typeof дверь.итогВиден === 'function') return дверь.итогВиден();
    return плашкаИтогаВидна();
  }

  function спрятатьПлашкуИтога() {
    var дверь = дверьЭкрана();
    if (дверь && typeof дверь.спрятатьИтог === 'function') { дверь.спрятатьИтог(); return; }
    if (экранИтога) экранИтога.classList.remove('экран--виден');
  }

  function вернутьПлашкуИтога() {
    var дверь = дверьЭкрана();
    if (дверь && typeof дверь.показатьИтог === 'function') { дверь.показатьИтог(); return; }
    if (экранИтога) экранИтога.classList.add('экран--виден');
  }

  function показать() {
    if (!экранПравил) return;
    if (!открыты()) {
      плашкаИтогаБылаВидна = плашкаИтогаВидна();
    }
    экранПравил.classList.add('экран--виден');
    if (экранДоски) экранДоски.classList.remove('экран--виден');
    if (плашкаИтогаБылаВидна) спрятатьПлашкуИтога();
    // Открыли во второй раз — читать начинают с начала, а не с места прошлой прокрутки
    var список = экранПравил.querySelector('.правила');
    if (список) список.scrollTop = 0;
  }

  function спрятать() {
    if (экранПравил) экранПравил.classList.remove('экран--виден');
    if (экранДоски) экранДоски.classList.add('экран--виден');
    if (плашкаИтогаБылаВидна) вернутьПлашкуИтога();
    плашкаИтогаБылаВидна = false;
  }

  if (кнопкаОткрыть) кнопкаОткрыть.addEventListener('click', показать);
  if (кнопкаНазад) кнопкаНазад.addEventListener('click', спрятать);

  window.ШашкиКакИграть = { показать: показать, спрятать: спрятать, открыты: открыты };
})();
