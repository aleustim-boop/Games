'use strict';

/* =====================================================================
   ШАШКИ — «ПОХВАСТАТЬСЯ» ПОБЕДОЙ.

   После победы над роботом человек хочет показать её друзьям — и это
   лучший повод позвать их в игру. Кнопка на плашке итога отправляет
   в чат по выбору короткое сообщение и ссылку на игру. Кому слать,
   решает человек; за него игра не хвастается.

   ДОРОГА К ЧАТУ НЕ ЗДЕСЬ. Она одна на обе игры и живёт у сети:
   «Сеть.похвастаться(описание)» → обещание { отправлено, способ },
   никогда не срывается. Здесь только кнопка, условия показа
   и описание победы — ровно как у дурака (см. «похвастаться»
   в js/game.js). Пока двери на странице нет — нет и кнопки: молчащая
   кнопка хуже отсутствующей.

   Кнопку видит только победитель, только против робота (вдвоём с одного
   телефона хвастаться некому и нечем) и только внутри Telegram —
   вне его слать некуда.

   Наружу: window.ШашкиПохвастаться = { показать({победа, уровень}), спрятать }.
   Зовёт их экран: «показать» — с плашкой итога, «спрятать» — с новой партией.
   ===================================================================== */

(function () {
  var кнопка = document.getElementById('кнопка-похвастаться');
  /* Уровень робота в творительном падеже: «над сложным ботом». */
  var УРОВЕНЬ_В_ТВОРИТЕЛЬНОМ = { 'лёгкий': 'лёгким', 'обычный': 'обычным', 'сложный': 'сложным' };
  /* Сколько ждём ответа двери, прежде чем вернуть кнопке подпись. Дорога
     обещает не срываться, но чужому обещанию верим с оглядкой: кнопка
     не должна навсегда остаться «Готовим…». */
  var ЖДЁМ_ХВАСТОВСТВО = 6000;

  var уровеньПобеды = 'обычный';   // с каким роботом выиграли — для описания

  /** Открыта ли игра внутри Telegram. Не в Telegram слать некуда. */
  function этоВнутриTelegram() {
    try {
      var приложение = window.Telegram && window.Telegram.WebApp;
      return !!(приложение && приложение.initData);
    } catch (ошибка) {
      return false;
    }
  }

  /** Есть ли на странице дверь к чату. */
  function дверьЕсть() {
    return !!(window.Сеть && typeof window.Сеть.похвастаться === 'function');
  }

  /**
   * Слова для чата. Коротко и без хвастовства за человека: результат,
   * соперник, приглашение. Ссылку приписывает дорога — она одна знает
   * адрес игры. Сервер собирает свой текст сам по тем же полям (чужой
   * текст бот не рассылает), поэтому правило одно и записано здесь:
   *   «Победа в шашках над сложным ботом. Сыграем?»
   */
  function словаПобедыДляЧата(уровень) {
    var бот = (УРОВЕНЬ_В_ТВОРИТЕЛЬНОМ[уровень] || 'обычным') + ' ботом';
    return 'Победа в шашках над ' + бот + '. Сыграем?';
  }

  /** Чем описать победу для двери: поля для сервера и готовые слова для запасного пути. */
  function описаниеПобеды() {
    var серия = 0;
    try {
      if (window.ШашкиРекорды && typeof window.ШашкиРекорды.серия === 'function') {
        серия = window.ШашкиРекорды.серия();
      }
    } catch (ошибка) { серия = 0; }
    return {
      игра: 'шашки',
      исход: 'победа',
      соперники: 'боты',      // партии с людьми по сети в шашках пока нет
      уровень: уровеньПобеды,
      игроков: 2,             // за доской всегда двое
      парами: false,
      переводной: false,
      серия: серия,
      слова: словаПобедыДляЧата(уровеньПобеды)
    };
  }

  /** Что написать на кнопке по ответу двери. Закрыл выбор чата — кнопка как была. */
  function словаОбОтправке(ответ) {
    if (!ответ) return 'Не вышло';
    if (ответ.отправлено === true) return 'Отправлено';
    if (ответ.способ === 'буфер') return 'Ссылка скопирована';
    if (ответ.способ === 'чат') return 'Выбираем чат…';
    return 'Похвастаться';
  }

  function подписать(текст, занята) {
    if (!кнопка) return;
    кнопка.textContent = текст;
    кнопка.disabled = занята === true;
  }

  function похвастаться() {
    if (!кнопка || кнопка.classList.contains('скрыт') || !дверьЕсть()) return;
    подписать('Готовим…', true);
    var ответили = false;
    var принять = function (ответ) {
      if (ответили) return;
      ответили = true;
      подписать(словаОбОтправке(ответ), false);
    };
    Promise.resolve()
      .then(function () { return window.Сеть.похвастаться(описаниеПобеды()); })
      .then(принять, function () { принять(null); });
    setTimeout(function () { принять(null); }, ЖДЁМ_ХВАСТОВСТВО);
  }

  /**
   * Показать кнопку вместе с плашкой итога — если есть чем и кому хвастаться.
   * итог.победа — выиграл ли человек у робота; итог.уровень — у какого.
   * Подпись возвращаем прежнюю: после прошлой партии могло остаться «Отправлено».
   */
  function показать(итог) {
    if (!кнопка) return;
    уровеньПобеды = (итог && итог.уровень) || 'обычный';
    var можно = !!(итог && итог.победа) && этоВнутриTelegram() && дверьЕсть();
    подписать('Похвастаться', false);
    кнопка.classList.toggle('скрыт', !можно);
  }

  function спрятать() {
    if (кнопка) кнопка.classList.add('скрыт');
  }

  if (кнопка) кнопка.addEventListener('click', похвастаться);

  window.ШашкиПохвастаться = { показать: показать, спрятать: спрятать };
})();
