'use strict';

/* =====================================================================
   ШАХМАТЫ — ЛОББИ. Каркас дурака, четыре карточки-входа на первом шаге
   («Играть онлайн», «Играть с ботом», «Вдвоём на этом устройстве»,
   «Пригласить друзей») — правка 24.09 (владелец: «кнопку играть на этом
   устройстве вдвоём нужно сделать в том же стиле что и играть онлайн
   или с ботом и сразу под кнопкой играть с ботом»; «Пригласить друзей»
   тоже должна работать, не быть «скоро», как в дураке). Настройка
   соперника (сложность бота, контроль времени) переехала на второй
   шаг — «экран-лобби-бот», его открывает карточка «Играть с ботом»,
   а саму партию заводит уже кнопка «Начать» там.

   ЧЕГО ЗДЕСЬ НЕТ. Ни одного правила игры, ни одного запроса к серверу
   за СТОЛ (сетевых шахмат нет вовсе — карточка «Онлайн» честно
   выключена). «Пригласить друзей» — не за стол, а в само приложение,
   и сети для неё не нужно: дверь window.Сеть.пригласитьВПриложение
   даёт отдельный маленький файл js/похвастаться.js (тот же, что у
   дурака и шашек), а не полный js/сеть.js. Этот файл только показывает
   нужный экран вместо доски и нажимает за человека уже существующие
   кнопки — те же, что были всегда. Второй дороги к партии или к боту
   этот файл не заводит.

   ЗАПАСНОЙ ВИД. В шахматы.html #экран-шахмат по-прежнему помечен
   классом «экран--виден» — это ЕГО вид по умолчанию. Не загрузится
   этот файл (сбой сети, старая страница в памяти телефона) — ничего
   не изменится, страница откроется сразу на доске, как и раньше.
   Загрузится — сам спрячет доску и покажет лобби вместо неё.

   ПОЧЕМУ ПОКАЗ ЭКРАНОВ УСТРОЕН СВОИМИ РУКАМИ, А НЕ ПОДМЕНОЙ ДВЕРИ,
   КАК У ШАШЕК. У шашек показ экранов шёл через одну дверь на window
   (window.ШашкиРежимы.показатьПоИмени), и лобби просто подменяло её.
   У шахмат такой двери наружу нет — «показатьЭкранШахмат» живёт
   закрытой внутри js/шахматы-экран.js (трогать этот файл нельзя,
   так решено в задании). Поэтому здесь — прямое переключение классов
   «экран--виден» между #экран-лобби и #экран-шахмат, а два места,
   где доска могла бы остаться скрытой позади лобби («Как играть»
   и «Оформление», открытые прямо из лобби через переходник «⋯»),
   подчищены вторым слушателем на тех же строках листа — тем же
   приёмом, каким шашки навесили второй слушатель на «кнопка-в-меню-
   шашки» (см. их js/шашки-лобби.js).

   ЧТО ДОЧИНЕНО ПРАВКОЙ js/шахматы-экран.js (тот файл теперь тоже в
   задании, а не вне его). «В меню» с доски (кнопка «‹» и строка листа
   «⋯») ведёт СНАЧАЛА в лобби и только уже оттуда — на витрину
   (index.html): решает это сама «уйтиНаВитрину» в js/шахматы-экран.js,
   глядя на класс «экран--виден» у #экран-лобби, а не переходит адресом
   напрямую. Пункт «Настройки» в меню самого Telegram тоже открывает
   лист «⋯», пока человек на лобби: «экран-лобби» стоит в списке
   «экраныСЛистом» рядом с «экран-шахмат» всё в том же файле. «Оформление»
   и «Как играть», открытые через «⋯» с лобби, при «Назад» возвращают
   тоже в лобби, а не на доску с чужой, никем не начатой партией —
   за это отвечает «местоДоСлужебного», тоже в js/шахматы-экран.js.

   ПРОВЕРКА БЕЗ БРАУЗЕРА. Ниже, до первого обращения к document, лежат
   только чистые данные и функции (уровень бота, слово о серии побед) —
   их достаёт штабная проверка через module.exports, как это устроено
   в js/нижние-вкладки.js и js/лист-ещё.js.
   ===================================================================== */

(function () {
  /* -------------------------------------------------------------------
     СЛОЖНОСТЬ БОТА: чистые данные, без DOM.

     Ключ памяти НОВЫЙ: до этого лобби выбор уровня жил только в
     переменной js/шахматы-экран.js («выбранныйУровень») и не переживал
     перезапуск игры — переносить в этом смысле было нечего. Имя —
     латиницей, как и остальные ключи сборника. */
  const КЛЮЧ_УРОВНЯ = 'chess_bot_level';
  const УРОВНИ = ['лёгкий', 'обычный', 'сложный'];

  function проверитьУровень(уровень) {
    return УРОВНИ.indexOf(уровень) !== -1 ? уровень : 'обычный';
  }

  /* -------------------------------------------------------------------
     КОНТРОЛЬ ВРЕМЕНИ (Э3): тот же приём, что и уровень бота выше —
     чистые данные без DOM, свой ключ памяти (новый — переносить нечего),
     действует и на игру с ботом, и на игру вдвоём. */
  const КЛЮЧ_КОНТРОЛЯ = 'chess_time_control';
  const КОНТРОЛИ = ['нет', 'блиц', 'рапид', 'классика'];

  function проверитьКонтроль(контроль) {
    return КОНТРОЛИ.indexOf(контроль) !== -1 ? контроль : 'нет';
  }

  /* Слово при числе побед подряд: «1 победа», «2 победы», «5 побед». */
  function словоПобед(сколько) {
    const остаток10 = сколько % 10;
    const остаток100 = сколько % 100;
    if (остаток100 >= 11 && остаток100 <= 14) return 'побед';
    if (остаток10 === 1) return 'победа';
    if (остаток10 >= 2 && остаток10 <= 4) return 'победы';
    return 'побед';
  }

  /** Строка карточки профиля про серию — та же честная фраза, что
   *  в таблице рекордов (см. «Побед подряд…» в js/шахматы-рекорды.js). */
  function строкаСерии(серия) {
    const число = Number(серия) || 0;
    return число > 0 ? (число + ' ' + словоПобед(число) + ' подряд') : 'Побед подряд пока нет';
  }

  /* -------------------------------------------------------------------
     ДАЛЬШЕ — ТОЛЬКО БРАУЗЕРНАЯ ЧАСТЬ. В Node (штабная проверка чистых
     функций выше) документа нет, и здесь всё останавливается — сами
     функции и константа ключа всё равно уйдут наружу, см. низ файла.
     ------------------------------------------------------------------- */
  if (typeof document !== 'undefined') {
    const лобби = document.getElementById('экран-лобби');
    const доска = document.getElementById('экран-шахмат');
    const шагБота = document.getElementById('экран-лобби-бот');
    if (!лобби || !доска || !шагБота) return;   // старая страница без этой разметки — жить нечем

    /* «Играть с ботом» / «Играть вдвоём» под доской (Э3) прячем ОТСЮДА,
       а не классом «скрыт» прямо в шахматы.html: до этой строки мы уже
       точно знаем, что сам файл лобби подключился и разметка на месте.
       Спрячь их в разметке — запасной вид («лобби не загрузилось —
       страница остаётся на прежней доске», см. шапку файла) потерял бы
       вообще всякий способ начать партию: у ряда уровней (Э2) есть
       значение по умолчанию «Обычный», а у этих кнопок замены нет. */
    const кнопкаСБотомДоска = document.getElementById('кнопка-с-ботом');
    const кнопкаВдвоёмДоска = document.getElementById('кнопка-вдвоём');
    if (кнопкаСБотомДоска) кнопкаСБотомДоска.classList.add('скрыт');
    if (кнопкаВдвоёмДоска) кнопкаВдвоёмДоска.classList.add('скрыт');

    /* Память телефона — свой маленький try/catch, как и в остальных
       файлах шахмат (js/шахматы-экран.js, js/шахматы-рекорды.js):
       запрещённая память не должна ронять лобби, просто уровень
       не запомнится. */
    function прочитатьУровень() {
      try {
        return проверитьУровень(window.localStorage.getItem(КЛЮЧ_УРОВНЯ));
      } catch (ошибка) {
        return 'обычный';
      }
    }

    function записатьУровень(уровень) {
      try {
        window.localStorage.setItem(КЛЮЧ_УРОВНЯ, уровень);
      } catch (ошибка) { /* запрещённая память — не повод ломать лобби */ }
    }

    let текущийУровень = прочитатьУровень();

    /* ---------- Контроль времени (Э3) ---------- */

    function прочитатьКонтроль() {
      try {
        return проверитьКонтроль(window.localStorage.getItem(КЛЮЧ_КОНТРОЛЯ));
      } catch (ошибка) {
        return 'нет';
      }
    }

    function записатьКонтроль(контроль) {
      try {
        window.localStorage.setItem(КЛЮЧ_КОНТРОЛЯ, контроль);
      } catch (ошибка) { /* запрещённая память — не повод ломать лобби */ }
    }

    let текущийКонтроль = прочитатьКонтроль();

    function нажать(id) {
      const кнопка = document.getElementById(id);
      if (кнопка) кнопка.click();
    }

    /* ---------- Сложность бота ---------- */

    const кнопкиУровня = {
      'лёгкий': document.getElementById('лобби-уровень-лёгкий'),
      'обычный': document.getElementById('лобби-уровень-обычный'),
      'сложный': document.getElementById('лобби-уровень-сложный')
    };

    function отметитьУровеньВЛобби(уровень) {
      for (const имя in кнопкиУровня) {
        const кнопка = кнопкиУровня[имя];
        if (!кнопка) continue;
        const выбрана = имя === уровень;
        кнопка.classList.toggle('переключатель__вариант--выбран', выбрана);
        кнопка.setAttribute('aria-checked', выбрана ? 'true' : 'false');
      }
    }

    for (const имя in кнопкиУровня) {
      const кнопка = кнопкиУровня[имя];
      if (!кнопка) continue;
      кнопка.addEventListener('click', function () {
        текущийУровень = имя;
        записатьУровень(текущийУровень);
        отметитьУровеньВЛобби(текущийУровень);
      });
    }
    отметитьУровеньВЛобби(текущийУровень);

    const кнопкиКонтроля = {
      'нет': document.getElementById('лобби-время-нет'),
      'блиц': document.getElementById('лобби-время-блиц'),
      'рапид': document.getElementById('лобби-время-рапид'),
      'классика': document.getElementById('лобби-время-классика')
    };

    /* Правка 24.09 (шаг бота приведён к виду шашек): кнопки контроля
       времени теперь на классе «.кнопка.кнопка--выбор» (плашка у КАЖДОГО
       варианта, не только у выбранного — как в #экран-бота-шашек шашек),
       поэтому и подсвечиваем их классом «кнопка--активная», как читает
       правило «.кнопка.кнопка--выбор.кнопка--активная» в style.css.
       У сложности бота класс кнопок прежний («переключатель__вариант»),
       её подсветку не трогаем — см. отметитьУровеньВЛобби выше. */
    function отметитьКонтрольВЛобби(контроль) {
      for (const имя in кнопкиКонтроля) {
        const кнопка = кнопкиКонтроля[имя];
        if (!кнопка) continue;
        const выбран = имя === контроль;
        кнопка.classList.toggle('кнопка--активная', выбран);
        кнопка.setAttribute('aria-checked', выбран ? 'true' : 'false');
      }
    }

    for (const имя in кнопкиКонтроля) {
      const кнопка = кнопкиКонтроля[имя];
      if (!кнопка) continue;
      кнопка.addEventListener('click', function () {
        текущийКонтроль = имя;
        записатьКонтроль(текущийКонтроль);
        отметитьКонтрольВЛобби(текущийКонтроль);
      });
    }
    отметитьКонтрольВЛобби(текущийКонтроль);

    /* ---------- Карточка профиля ---------- */

    /* Фото профиля в кружке аватара лобби — тот же приём, что у дурака
       (см. «освежитьАватар» в js/дурак-путь.js) и у шашек (js/шашки-
       лобби.js): единственная дверь — window.Телеграм.фотоИгрока(),
       картинка грузится втихую через new Image(), и класс-переменную
       красим только в её onload — иначе битый адрес показал бы пустой
       кружок вместо нарисованного человечка. Память последнего
       подтверждённого адреса — чтобы не перегружать одну и ту же
       картинку при каждом показе лобби. Своего id у узла нет
       (в шахматы.html — просто класс «аватар» внутри кнопки
       «лобби-профиль»), поэтому ищем его querySelector'ом. */
    let последнийЗагруженныйАдресАватара = '';
    function освежитьАватар() {
      const узелАватара = document.querySelector('#лобби-профиль .аватар');
      if (!узелАватара) return;
      const адрес = String((window.Телеграм && typeof window.Телеграм.фотоИгрока === 'function'
        ? window.Телеграм.фотоИгрока() : '') || '');
      if (!адрес) {
        узелАватара.classList.remove('аватар--фото');
        узелАватара.style.removeProperty('--фото-аватара');
        return;
      }
      const показатьЗагруженное = function () {
        узелАватара.style.setProperty('--фото-аватара', 'url("' + адрес + '")');
        const принялось = узелАватара.style.getPropertyValue('--фото-аватара').trim() !== '';
        if (!принялось) {
          узелАватара.classList.remove('аватар--фото');
          узелАватара.style.removeProperty('--фото-аватара');
          return;
        }
        узелАватара.classList.add('аватар--фото');
      };
      if (адрес === последнийЗагруженныйАдресАватара) {
        показатьЗагруженное();
        return;
      }
      const картинка = new Image();
      картинка.onload = function () {
        последнийЗагруженныйАдресАватара = адрес;
        // Лобби могли уже закрыть, пока шла загрузка — красить нечего.
        if (!document.body.contains(узелАватара)) return;
        показатьЗагруженное();
      };
      картинка.onerror = function () { /* сеть подвела — молча оставляем человечка */ };
      картинка.src = адрес;
    }

    function освежитьПрофиль() {
      const имя = document.getElementById('лобби-имя');
      if (имя) {
        const изTelegram = window.Телеграм && typeof window.Телеграм.имяИгрока === 'function'
          ? String(window.Телеграм.имяИгрока() || '').trim() : '';
        имя.textContent = изTelegram || 'Вы';
      }
      освежитьАватар();
      const серия = document.getElementById('лобби-серия-текст');
      if (серия) {
        const число = window.ШахматыРекорды && typeof window.ШахматыРекорды.серия === 'function'
          ? window.ШахматыРекорды.серия() : 0;
        серия.textContent = строкаСерии(число);
      }
    }
    освежитьПрофиль();

    /* Профиль освежаем не только при загрузке страницы, но каждый раз,
       когда лобби становится видимым, — двумя путями сразу:
         1) js/шахматы-экран.js возвращает в лобби НАПРЯМУЮ переключением
            класса «экран--виден» (кнопка «Назад», стрелка Telegram, «В меню»
            из листа) — этот файл о существовании освежитьПрофиль не знает
            и знать не должен (граница между файлами). Поэтому сторожим сам
            класс: как только лобби становится видимым, откуда бы показ ни
            пришёл, серия и имя обновляются — иначе после партии в лобби
            висела бы вчерашняя серия побед;
         2) в настоящем Telegram имя игрока даёт telegram-web-app.js —
            он подключён с «defer» и может ответить ПОЗЖЕ, чем выполнился
            этот файл; тогда лобби успевает показать «Вы» раньше, чем стало
            известно настоящее имя. Событие load окна наступает заведомо
            позже — повторяем освежение по нему, и имя не остаётся навсегда
            заглушкой. */
    if (typeof MutationObserver === 'function') {
      const сторожЛобби = new MutationObserver(function () {
        if (лобби.classList.contains('экран--виден')) освежитьПрофиль();
      });
      сторожЛобби.observe(лобби, { attributes: true, attributeFilter: ['class'] });
    }
    try {
      window.addEventListener('load', освежитьПрофиль);
    } catch (ошибка) { /* нет окна — освежать нечего */ }

    /* ---------- Показ лобби и доски ----------

       Своей публичной двери переключения экранов у шахмат нет (см.
       пояснение в шапке файла), поэтому переключаем классы сами —
       только между двумя узлами, которые здесь и нужны. */

    function показатьЛобби() {
      доска.classList.remove('экран--виден');
      шагБота.classList.remove('экран--виден');
      лобби.classList.add('экран--виден');
      освежитьПрофиль();   // серия могла обновиться после партии
    }

    function показатьДоску() {
      лобби.classList.remove('экран--виден');
      шагБота.classList.remove('экран--виден');
      доска.classList.add('экран--виден');
    }

    /* Второй шаг — настройка бота (сложность, контроль времени, «Начать»).
       Партию отсюда ещё не заводим, только показываем экран. */
    function показатьШагБота() {
      лобби.classList.remove('экран--виден');
      доска.classList.remove('экран--виден');
      шагБота.classList.add('экран--виден');
    }

    показатьЛобби();   // главный экран страницы — лобби, а не доска

    /* ---------- Карточки входов: переходники на уже существующие кнопки ----------
       Ни одна не заводит новую дорогу к партии или к боту — только
       нажимает узел, который уже слушает js/шахматы-экран.js, и следом
       переключает видимый экран на доску. */

    const кнопкаБоты = document.getElementById('лобби-боты');
    if (кнопкаБоты) {
      // Карточка теперь только открывает второй шаг с настройками —
      // саму партию заводит там кнопка «Начать» (см. ниже).
      кнопкаБоты.addEventListener('click', показатьШагБота);
    }

    const кнопкаБотНазад = document.getElementById('кнопка-лобби-бот-назад');
    if (кнопкаБотНазад) кнопкаБотНазад.addEventListener('click', показатьЛобби);

    /* Нижняя кнопка «Назад» (правка 24.09, по образцу «кнопка-бота-назад»
       у шашек): верхняя стрелка «‹» видна только в браузере, а внутри
       Telegram нужен видимый способ вернуться на первый шаг — слушает
       тот же показатьЛобби, что и стрелка выше. */
    const кнопкаБотНазадВнизу = document.getElementById('лобби-бот-назад');
    if (кнопкаБотНазадВнизу) кнопкаБотНазадВнизу.addEventListener('click', показатьЛобби);

    const кнопкаБотНачать = document.getElementById('лобби-бот-начать');
    if (кнопкаБотНачать) {
      кнопкаБотНачать.addEventListener('click', function () {
        // Сначала отмечаем уровень и контроль времени на скрытых кнопках
        // под доской — так js/шахматы-экран.js запомнит именно их, потом
        // жмём саму «Играть с ботом»: она заводит партию.
        нажать('уровень-' + текущийУровень);
        нажать('время-' + текущийКонтроль);
        нажать('кнопка-с-ботом');
        показатьДоску();
      });
    }

    const кнопкаВдвоём = document.getElementById('лобби-вдвоём');
    if (кнопкаВдвоём) {
      кнопкаВдвоём.addEventListener('click', function () {
        нажать('время-' + текущийКонтроль);
        нажать('кнопка-вдвоём');
        показатьДоску();
      });
    }

    /* ---------- «Пригласить друзей» ----------
       Тот же приём, что js/дурак-путь.js (пригласитьДрузей): зов не
       за стол, а в само приложение — дверь window.Сеть.пригласитьВПри-
       ложение (js/похвастаться.js). Дверь никогда не срывается, но
       ответ всё равно нужно показать — молчание на нажатие выглядело
       бы как беда. Показываем весть прямо на подписи карточки и через
       паузу возвращаем прежние слова, своих всплывающих окон не заводим.
       Числа те же, что у дурака: 6 секунд ждём дверь, 2.5 секунды держим
       весть на подписи. */
    const ЖДЁМ_ПРИГЛАШЕНИЕ = 6000;
    const ВЕСТЬ_ДЕРЖИТСЯ = 2500;
    let приглашениеИдёт = false;

    /** Слова о результате — тот же приём, что «словаОПриглашении» у дурака. */
    function словаОПриглашении(ответ) {
      if (ответ && ответ.отправлено === true) return 'Отправлено';
      if (ответ && ответ.способ === 'буфер') return 'Ссылка скопирована';
      if (ответ && ответ.способ === 'чат') return 'Выбираем чат…';
      return 'Не вышло — попробуйте ещё раз';
    }

    function пригласитьДрузей() {
      if (приглашениеИдёт) return;
      if (!window.Сеть || typeof window.Сеть.пригласитьВПриложение !== 'function') return;
      const карточка = document.getElementById('лобби-друзья');
      const подпись = карточка ? карточка.querySelector('.карточка-входа__подпись') : null;
      const исходнаяПодпись = подпись ? подпись.textContent : '';
      приглашениеИдёт = true;
      let ответили = false;
      const принять = function (ответ) {
        if (ответили) return;
        ответили = true;
        приглашениеИдёт = false;
        if (!подпись) return;
        подпись.textContent = словаОПриглашении(ответ);
        setTimeout(function () { подпись.textContent = исходнаяПодпись; }, ВЕСТЬ_ДЕРЖИТСЯ);
      };
      Promise.resolve()
        .then(function () { return window.Сеть.пригласитьВПриложение(); })
        .then(принять, function () { принять(null); });
      setTimeout(function () { принять(null); }, ЖДЁМ_ПРИГЛАШЕНИЕ);
    }

    const кнопкаДрузья = document.getElementById('лобби-друзья');
    if (кнопкаДрузья) кнопкаДрузья.addEventListener('click', пригласитьДрузей);

    /* «Играть онлайн» выключена в разметке (disabled) — своей двери
       и слушателя ей не нужно: сетевых шахмат нет вовсе, а не «скоро
       подключим». */

    const кнопкаПрофиль = document.getElementById('лобби-профиль');
    if (кнопкаПрофиль) {
      кнопкаПрофиль.addEventListener('click', function () {
        if (window.ЭкранРейтинга) window.ЭкранРейтинга.открытьСчёт('шахматы');
      });
    }

    /* ---------- Верхняя строка лобби: переходники на кнопки доски ----------
       «‹» и «⋯» у лобби свои узлы (id другой — «кнопка-назад» уже занят
       кнопкой доски), но слушать им нечего своего: они просто нажимают
       уже существующие кнопки доски и получают то же поведение. */

    const кнопкаНазад = document.getElementById('кнопка-лобби-назад');
    if (кнопкаНазад) кнопкаНазад.addEventListener('click', function () { нажать('кнопка-назад'); });

    /* «⋯» на лобби своего слушателя не заводит: js/лист-ещё.js уже открывает
       лист напрямую по её id — он в списке «идОткрывающих» рядом с «⋯» доски
       (см. js/шахматы-экран.js). Переходник сюда добавлял ВТОРОЙ слушатель
       на ту же кнопку («кнопка-игра-ещё» нажималась и своим, и этим кодом),
       и один тап открывал лист дважды. */

    /* ---------- Подчистка после «Как играть» и «Оформление» из лобби ----------

       Обе строки листа «⋯» показывают доску-семью экранов через закрытую
       «показатьЭкранШахмат» (js/шахматы-экран.js) — та не знает ни о
       лобби, ни о шаге бота и их класс «экран--виден» не трогает. Открой
       их прямо из лобби или с шага бота — экраны оказались бы видны
       разом. Второй слушатель на тех же кнопках (тот же приём, что у
       шашек с «кнопка-в-меню-шашки») чинит это в ту же прорисовку кадра:
       он ничего не решает сам, только прячет лобби и шаг бота, если
       остались видимыми. Безопасно вызывать и тогда, когда оба и так
       уже скрыты (обычный путь — с доски). */
    function спрятатьЛоббиПозжеПервогоСлушателя() {
      лобби.classList.remove('экран--виден');
      шагБота.classList.remove('экран--виден');
    }
    const кнопкаЛистОформление = document.getElementById('кнопка-лист-игры-оформление');
    if (кнопкаЛистОформление) кнопкаЛистОформление.addEventListener('click', спрятатьЛоббиПозжеПервогоСлушателя);
    const кнопкаЛистПравила = document.getElementById('кнопка-лист-игры-правила');
    if (кнопкаЛистПравила) кнопкаЛистПравила.addEventListener('click', спрятатьЛоббиПозжеПервогоСлушателя);
  }

  /* Наружу — только чистые данные и функции без DOM, для проверки
     в Node (штаб/…), как у js/нижние-вкладки.js и js/лист-ещё.js. */
  const ШахматыЛобби = {
    проверитьУровень: проверитьУровень, строкаСерии: строкаСерии, КЛЮЧ_УРОВНЯ: КЛЮЧ_УРОВНЯ,
    проверитьКонтроль: проверитьКонтроль, КЛЮЧ_КОНТРОЛЯ: КЛЮЧ_КОНТРОЛЯ
  };
  if (typeof module !== 'undefined' && module.exports) module.exports = ШахматыЛобби;
  if (typeof window !== 'undefined') window.ШахматыЛобби = ШахматыЛобби;
})();
