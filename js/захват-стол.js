    ПОРОГ_МАЛОГО_ШАНСА: ПОРОГ_МАЛОГО_ШАНСА,
    ПОРОГ_ПРОТЯЖКИ_PX: ПОРОГ_ПРОТЯЖКИ_PX,
    ДОЛГОЕ_КАСАНИЕ_МС: ДОЛГОЕ_КАСАНИЕ_МС,
    ДВОЙНОЕ_КАСАНИЕ_МС: ДВОЙНОЕ_КАСАНИЕ_МС,
