// «Захват»: стол, часть 1 (этап В6) — полоса игроков, панель действий, лист приказа, карточка
// области, слой шайб и пилюль поверх холста. Жесты (касания, протяжка, долгое касание) — этап В7.
// Из js выходят только классы, атрибуты, текст и CSS-переменные-числа (--x, --y, --размер);
// цвета, размеры и картинки задаёт оформление, а рисует их только Кодекс (правило владельца).
// Правила не раздваиваются: черновик проверяет js/захват-правила.js, стол лишь показывает отказ.
// Слова про игрока — без рода (ТЗ 8.5а): «сдача», «играет бот», «выбывает».
// Наружу window.ЗахватСтол и module.exports; документ приходит доводом, чтобы стол жил и на node.
(function () {
  'use strict';

  const Правила = (typeof window !== 'undefined' && window.ЗахватПравила)
    ? window.ЗахватПравила
    : require('./захват-правила.js');
  const КартаВид = (typeof window !== 'undefined' && window.ЗахватКартаВид)
    ? window.ЗахватКартаВид
    : require('./захват-карта-вид.js');

  const ДЛИНА_ИМЕНИ = 8;
  const СЛОВА = {
    выбыл: 'выбывает',
    сдача: 'сдача',
    ушёл: 'играет бот',
    бот: 'бот',
    спит: 'спит'
  };
  const ЗАПЕРТО_ПОСЛЕ_ГОТОВО = true;
  const ПИЛЮЛИ_ПОСЛЕ_ГОТОВО = false;
  const ОТКАЗ_ПОСЛЕ_ГОТОВО = 'Приказы отправлены — нажмите «Изменить», чтобы поправить';

  // ---------- мелкие помощники ----------

  function отказ(причина) {
    return { принято: false, причина: причина };
  }

  function успех() {
    return { принято: true, причина: null };
  }

  // Показать или спрятать узел общим классом «скрыт».
  function показать(узел, да) {
    if (!узел) return;
    if (да) узел.classList.remove('скрыт');
    else узел.classList.add('скрыт');
  }

  function включить(узел, да) {
    if (!узел) return;
    if (да) узел.removeAttribute('disabled');
    else узел.setAttribute('disabled', '');
  }

  function класс(узел, имя, да) {
    if (да) узел.classList.add(имя);
    else узел.classList.remove(имя);
  }

  function обрезатьИмя(имя) {
    const буквы = Array.from(String(имя));
    return буквы.length > ДЛИНА_ИМЕНИ ? буквы.slice(0, ДЛИНА_ИМЕНИ).join('') + '…' : буквы.join('');
  }

  // «1 войско», «2 войска», «5 войск».
  function войск(n) {
    const последние = n % 100;
    const последняя = n % 10;
    if (последние >= 11 && последние <= 14) return n + ' войск';
    if (последняя === 1) return n + ' войско';
    if (последняя >= 2 && последняя <= 4) return n + ' войска';
    return n + ' войск';
  }

  function копия(черновик) {
    return JSON.parse(JSON.stringify(черновик));
  }

  function поставлено(черновик) {
    return Object.keys(черновик.расстановка).reduce(function (сумма, к) { return сумма + черновик.расстановка[к]; }, 0);
  }

  // ---------- сам стол ----------

  // параметры: документ; рисункиЕсть (до пачки Кодекса шайбы, пилюли и значки скрыты);
  // слушатели: { приИзменении(черновик), приГотово(черновик), приИзменить() } — для экрана и сети.
  function создать(параметры) {
    const настройки = параметры || {};
    const документ = настройки.документ || (typeof document !== 'undefined' ? document : null);
    if (!документ) throw new Error('Столу нужен документ');
    const слушатели = настройки.слушатели || {};
    const узел = function (id) { return документ.getElementById(id); };

    const состояние = {
      партия: null,
      мой: null,
      инфо: { имена: {}, готовы: {}, боты: {}, спят: {} },
      черновик: { расстановка: {}, приказы: [] },
      история: [],
      готов: false,
      вопросОбОстатке: false,
      рисункиЕсть: !!настройки.рисункиЕсть,
      лист: null,
      слой: null,
      сообщение: ''
    };

    // ----- общие вычисления -----

    function карта() {
      return Правила.картаПартии(состояние.партия);
    }

    function имяОбласти(номер) {
      return карта().области[номер - 1].имя;
    }

    function имяИгрока(ключ) {
      if (ключ === состояние.мой) return 'Вы';
      const имя = состояние.инфо.имена[ключ];
      if (имя) return имя;
      return 'Игрок ' + (состояние.партия.игроки.indexOf(ключ) + 1);
    }

    function вИгре() {
      return Правила.вИгре(состояние.партия, состояние.мой);
    }

    function осталосьПоставить() {
      return (состояние.партия.подкрепление[состояние.мой] || 0) - поставлено(состояние.черновик);
    }

    function запертоПослеГотово() {
      if (ЗАПЕРТО_ПОСЛЕ_ГОТОВО && состояние.готов) return отказ(ОТКАЗ_ПОСЛЕ_ГОТОВО);
      return null;
    }

    function сказатьОтказ(причина) {
      состояние.сообщение = причина;
      обновитьПодсказку();
    }

    // ----- полоса игроков (ТЗ 8.4) -----

    function меткаИгрока(ключ) {
      const п = состояние.партия;
      if (п.выбыли[ключ]) return СЛОВА.выбыл;
      if (п.сдались[ключ]) return СЛОВА.сдача;
      if (typeof п.ушлоВРаунде[ключ] === 'number') return СЛОВА.ушёл;
      if (состояние.инфо.боты[ключ]) return СЛОВА.бот;
      if (состояние.инфо.спят[ключ]) return СЛОВА.спит;
      return '';
    }

    function найтиВ(родитель, имяКласса) {
      return родитель.querySelector('.' + имяКласса);
    }

    function нарисоватьПолосуИгроков() {
      const п = состояние.партия;
      const фишки = узел('захват-игроки').children;
      for (let и = 0; и < фишки.length; и++) {
        const фишка = фишки[и];
        const ключ = п.игроки[и];
        показать(фишка, ключ !== undefined);
        if (ключ === undefined) continue;
        const цвет = КартаВид.цветХозяина(п, ключ);
        const значок = найтиВ(фишка, 'захват-игрок__значок');
        значок.setAttribute('class', 'захват-игрок__значок захват-игрок__значок--' + цвет);
        показать(значок, состояние.рисункиЕсть);
        найтиВ(фишка, 'захват-игрок__имя').textContent = обрезатьИмя(имяИгрока(ключ));
        const подсчёт = Правила.подкрепление(п, ключ);
        найтиВ(фишка, 'захват-игрок__счёт').textContent = подсчёт.областей + ' · ' + Правила.очки(п, ключ);
        найтиВ(фишка, 'захват-игрок__метка').textContent = меткаИгрока(ключ);
        // Только факт «готов»: чужих черновиков стол не знает и не показывает.
        let галка = найтиВ(фишка, 'захват-игрок__готов');
        if (!галка) {
          галка = документ.createElement('span');
          галка.setAttribute('class', 'захват-игрок__готов');
          фишка.appendChild(галка);
        }
        галка.textContent = состояние.инфо.готовы[ключ] && Правила.вИгре(п, ключ) ? '✓' : '';
        класс(фишка, 'захват-игрок--я', ключ === состояние.мой);
        класс(фишка, 'захват-игрок--вне', !Правила.вИгре(п, ключ));
      }
    }

    function нарисоватьСтрокуРаунда() {
      const п = состояние.партия;
      узел('захват-раунд').textContent = 'Раунд ' + п.раунд + ' из ' + п.всегоРаундов;
      const живые = п.игроки.filter(function (к) { return Правила.вИгре(п, к); });
      const готовых = живые.filter(function (к) { return состояние.инфо.готовы[к]; }).length;
      узел('захват-готовы').textContent = 'Готовы ' + готовых + '/' + живые.length;
    }

    // ----- подсказка и панель действий -----

    function текстПодсказки() {
      const п = состояние.партия;
      if (!вИгре()) return 'Вы выбыли — смотрите партию';
      if (состояние.вопросОбОстатке) return состояние.вопросОбОстатке;
      if (состояние.готов) {
        const ждём = п.игроки.filter(function (к) {
          return Правила.вИгре(п, к) && !состояние.инфо.готовы[к] && к !== состояние.мой;
        }).map(имяИгрока);
        return ждём.length ? 'Ждём: ' + ждём.join(', ') : 'Все готовы';
      }
      const осталось = осталосьПоставить();
      if (осталось > 0) return 'Поставьте войска: осталось ' + осталось;
      return 'Проведите от своей области к соседней';
    }

    function обновитьПодсказку() {
      const подсказка = узел('захват-подсказка');
      подсказка.textContent = состояние.сообщение || текстПодсказки();
      класс(подсказка, 'захват-подсказка--отказ', !!состояние.сообщение);
    }

    function обновитьПанель() {
      const готово = узел('захват-готово');
      готово.textContent = состояние.готов ? 'Изменить' : '✓ Готово';
      класс(готово, 'кнопка--главная', !состояние.готов);
      включить(готово, вИгре());
      включить(узел('захват-отменить'), вИгре() && !состояние.готов && состояние.история.length > 0);
    }

    function обновитьВсё() {
      нарисоватьСтрокуРаунда();
      нарисоватьПолосуИгроков();
      обновитьПанель();
      обновитьПодсказку();
      перерисоватьСлой();
    }

    function сообщитьОбИзменении() {
      if (слушатели.приИзменении) слушатели.приИзменении(копия(состояние.черновик));
    }

    // ----- правка черновика -----

    // Единственная дверь, через которую черновик меняется: сперва замок «Готово», затем правила.
    function применить(новый, подпись) {
      const замок = запертоПослеГотово();
      if (замок) { сказатьОтказ(замок.причина); return замок; }
      const проверка = Правила.проверитьЧерновик(состояние.партия, состояние.мой, новый);
      if (!проверка.принято) { сказатьОтказ(проверка.причина); return проверка; }
      состояние.история.push(копия(состояние.черновик));
      состояние.черновик = копия(новый);
      состояние.сообщение = '';
      состояние.вопросОбОстатке = false;
      обновитьВсё();
      сообщитьОбИзменении();
      return { принято: true, причина: null, что: подпись };
    }

    function поставитьВойска(область, сколько) {
      const новый = копия(состояние.черновик);
      новый.расстановка[область] = (новый.расстановка[область] || 0) + (сколько === undefined ? 1 : сколько);
      return применить(новый, 'расстановка');
    }

    function отменить() {
      const замок = запертоПослеГотово();
      if (замок) { сказатьОтказ(замок.причина); return замок; }
      if (!состояние.история.length) return отказ('Отменять нечего');
      состояние.черновик = состояние.история.pop();
      состояние.сообщение = '';
      состояние.вопросОбОстатке = false;
      обновитьВсё();
      сообщитьОбИзменении();
      return успех();
    }

    // ----- «Готово» и «Изменить» (ТЗ 3.3, 9) -----

    function поставитьОстатокВЧерновик() {
      const осталось = осталосьПоставить();
      const куда = Правила.кудаОстаток(состояние.партия, состояние.мой, состояние.черновик);
      if (осталось <= 0 || !куда) return null;
      const новый = копия(состояние.черновик);
      новый.расстановка[куда.область] = (новый.расстановка[куда.область] || 0) + осталось;
      return новый;
    }

    function подтвердитьГотово() {
      состояние.готов = true;
      состояние.сообщение = '';
      состояние.вопросОбОстатке = false;
      закрытьПриказ();
      обновитьВсё();
      if (слушатели.приГотово) слушатели.приГотово(копия(состояние.черновик));
      return успех();
    }

    // «Готово». При остатке подкрепления сперва вопрос: отдаёт { принято: false, вопрос, остаток }
    // и ждёт поставитьОстатокИГотово() или отмены вопроса через отказатьсяОтВопроса().
    function нажатьГотово() {
      if (состояние.готов) return отказ('Вы уже нажали «Готово»');
      if (!вИгре()) return отказ('Вы уже не в игре');
      const проверка = Правила.проверитьЧерновик(состояние.партия, состояние.мой, состояние.черновик);
      if (!проверка.принято) { сказатьОтказ(проверка.причина); return проверка; }
      const осталось = осталосьПоставить();
      if (осталось > 0) {
        const куда = Правила.кудаОстаток(состояние.партия, состояние.мой, состояние.черновик);
        const где = куда && куда.столица ? 'в столицу' : 'в самую большую область';
        состояние.вопросОбОстатке = 'Осталось ' + войск(осталось) + '. Поставить ' + где + '?';
        обновитьПодсказку();
        return { принято: false, причина: null, вопрос: состояние.вопросОбОстатке, остаток: осталось };
      }
      return подтвердитьГотово();
    }

    function поставитьОстатокИГотово() {
      const новый = поставитьОстатокВЧерновик();
      if (новый) {
        const итог = применить(новый, 'остаток');
        if (!итог.принято) return итог;
      }
      return подтвердитьГотово();
    }

    function отказатьсяОтВопроса() {
      состояние.вопросОбОстатке = false;
      обновитьПодсказку();
    }

    function изменить() {
      if (!состояние.готов) return отказ('Приказы ещё не отправлены');
      состояние.готов = false;
      состояние.сообщение = '';
      обновитьВсё();
      if (слушатели.приИзменить) слушатели.приИзменить();
      return успех();
    }

    function нажатьГотовоИлиИзменить() {
      return состояние.готов ? изменить() : нажатьГотово();
    }

    // ----- лист приказа (ТЗ 8.4.2) -----

    function приказНаПаре(из, в) {
      return состояние.черновик.приказы.filter(function (п) { return п.из === из && п.в === в; })[0] || null;
    }

    // Сколько ещё можно отправить из области: войска + поставлено − 1 − отправлено другими приказами.
    function сколькоМожноОтправить(из, в) {
      const п = состояние.партия;
      const другими = состояние.черновик.приказы
        .filter(function (пр) { return !(пр.из === из && пр.в === в) && пр.из === из; })
        .reduce(function (сумма, пр) { return сумма + пр.сколько; }, 0);
      return п.войска[из] + (состояние.черновик.расстановка[из] || 0) - 1 - другими;
    }

    function нарисоватьЛистПриказа() {
      const л = состояние.лист;
      const п = состояние.партия;
      узел('захват-приказ-заголовок').textContent = имяОбласти(л.из) + ' → ' + имяОбласти(л.в) + ' · ' + л.вид;
      const ползунок = узел('захват-приказ-ползунок');
      ползунок.setAttribute('min', '1');
      ползунок.setAttribute('max', String(Math.max(1, л.максимум)));
      ползунок.value = String(л.число);
      узел('захват-приказ-число').textContent = 'Отправить: ' + л.число + ' из ' + Math.max(1, л.максимум);
      const удар = л.вид === 'удар';
      показать(узел('захват-приказ-шанс'), удар);
      показать(узел('захват-приказ-потери'), удар);
      // Подкреплять соперника может только живой хозяин: у ничьей области строки нет (ТЗ 3.5).
      const чужая = удар && п.хозяева[л.в] !== null;
      показать(узел('захват-приказ-подкрепление'), чужая);
      if (удар) {
        const защитников = п.войска[л.в];
        узел('захват-приказ-шанс').textContent = 'Шанс взять: ' + Правила.процентШанса(л.число, защитников).текст;
        узел('захват-приказ-потери').textContent = 'Ожидаемые потери ≈ ' + Правила.ожидаемыеПотери(л.число, защитников);
      } else {
        узел('захват-приказ-шанс').textContent = '';
        узел('захват-приказ-потери').textContent = '';
      }
      узел('захват-приказ-подкрепление').textContent = чужая
        ? 'Соперник может подкрепиться — шанс по тому, что видно сейчас' : '';
      показать(узел('захват-приказ-убрать'), л.был);
    }

    // Открыть лист: по умолчанию — всё доступное (или число уже отданного приказа).
    function открытьПриказ(из, в) {
      const замок = запертоПослеГотово();
      if (замок) { сказатьОтказ(замок.причина); return замок; }
      const п = состояние.партия;
      if (п.хозяева[из] !== состояние.мой) return отказ('Приказ можно отдать только из своей области');
      const максимум = сколькоМожноОтправить(из, в);
      const был = приказНаПаре(из, в);
      if (максимум < 1 && !был) {
        const причина = 'Из этой области нечего отправлять: в ней должно остаться 1 войско';
        сказатьОтказ(причина);
        return отказ(причина);
      }
      состояние.лист = {
        из: из,
        в: в,
        вид: Правила.видПриказа(п, состояние.мой, из, в),
        максимум: максимум,
        число: был ? был.сколько : максимум,
        был: !!был
      };
      состояние.сообщение = '';
      нарисоватьЛистПриказа();
      показать(узел('захват-приказ'), true);
      return успех();
    }

    // Число меняют кнопки и ползунок, но оно не зажато молча: лишнее поймают правила при «Отдать приказ».
    function задатьЧисло(число) {
      if (!состояние.лист) return отказ('Лист приказа закрыт');
      const целое = Math.max(1, Math.round(Number(число)));
      состояние.лист.число = целое;
      нарисоватьЛистПриказа();
      return успех();
    }

    function добавитьВЛист(шаг) {
      if (!состояние.лист) return отказ('Лист приказа закрыт');
      const л = состояние.лист;
      return задатьЧисло(Math.min(Math.max(1, л.максимум), Math.max(1, л.число + шаг)));
    }

    function закрытьПриказ() {
      состояние.лист = null;
      показать(узел('захват-приказ'), false);
    }

    function отдатьПриказ() {
      if (!состояние.лист) return отказ('Лист приказа закрыт');
      const л = состояние.лист;
      const новый = копия(состояние.черновик);
      новый.приказы = новый.приказы.filter(function (п) { return !(п.из === л.из && п.в === л.в); });
      новый.приказы.push({ из: л.из, в: л.в, сколько: л.число });
      const итог = применить(новый, 'приказ');
      if (итог.принято) закрытьПриказ();
      return итог;
    }

    function убратьПриказ() {
      if (!состояние.лист) return отказ('Лист приказа закрыт');
      const л = состояние.лист;
      const новый = копия(состояние.черновик);
      новый.приказы = новый.приказы.filter(function (п) { return !(п.из === л.из && п.в === л.в); });
      const итог = применить(новый, 'приказ убран');
      if (итог.принято) закрытьПриказ();
      return итог;
    }

    // ----- карточка области (ТЗ 8.4.3) -----

    function открытьКарточку(область) {
      const п = состояние.партия;
      const к = карта();
      const о = к.области[область - 1];
      if (!о) return отказ('Нет такой области');
      узел('захват-карточка-имя').textContent = о.имя;
      const хозяин = п.хозяева[область];
      узел('захват-карточка-хозяин').textContent = хозяин === null ? 'Ничья область' : 'Хозяин: ' + имяИгрока(хозяин);
      узел('захват-карточка-войска').textContent = 'Войска: ' + п.войска[область];
      const край = к.края.filter(function (кр) { return кр.название === о.край; })[0];
      if (край) {
        const моих = край.области.filter(function (н) { return п.хозяева[н] === состояние.мой; }).length;
        узел('захват-карточка-край').textContent = край.название + ' · +' + край.прибавка +
          ' · у вас ' + моих + ' из ' + край.области.length;
      } else {
        узел('захват-карточка-край').textContent = '';
      }
      const столица = (п.столицы || []).some(function (с) { return с.область === область; });
      показать(узел('захват-карточка-столица'), столица);
      узел('захват-карточка-столица').textContent = столица ? (хозяин === null ? 'Столица, сейчас ничья' : 'Столица') : '';
      показать(узел('захват-карточка'), true);
      return успех();
    }

    function закрытьКарточку() {
      показать(узел('захват-карточка'), false);
    }

    // ----- слой шайб и пилюль поверх холста -----

    function создатьУзел(имяКласса, текст) {
      const у = документ.createElement('div');
      у.setAttribute('class', имяКласса);
      if (текст !== undefined) у.textContent = текст;
      return у;
    }

    // Места — только CSS-переменные-числа из расчёта В4; как узел выглядит — дело оформления.
    function поставитьМесто(у, x, y, размер) {
      у.style.setProperty('--x', String(Math.round(x * 100) / 100));
      у.style.setProperty('--y', String(Math.round(y * 100) / 100));
      if (размер !== undefined) у.style.setProperty('--размер', String(размер));
    }

    function нарисоватьСлой(раскладка) {
      const слой = узел('захват-слой');
      слой.replaceChildren();
      const п = состояние.партия;
      раскладка.шайбы.forEach(function (ш) {
        const имена = ['захват-шайба', 'захват-шайба--' + ш.цвет];
        if (ш.столица) имена.push('захват-шайба--столица');
        const у = создатьУзел(имена.join(' '));
        у.setAttribute('data-область', String(ш.область));
        поставитьМесто(у, ш.x, ш.y, ш.размер);
        у.appendChild(создатьУзел('захват-шайба__число', String(п.войска[ш.область])));
        if (ш.значок) {
          const з = создатьУзел('захват-шайба__значок захват-шайба__значок--' + ш.цвет);
          поставитьМесто(з, ш.значок.x, ш.значок.y, ш.значок.размер);
          у.appendChild(з);
        }
        показать(у, состояние.рисункиЕсть);
        слой.appendChild(у);
      });
      раскладка.пилюли.forEach(function (пил) {
        const плюс = состояние.черновик.расстановка[пил.область] || 0;
        // ТЗ 8.4.1: «+N» видна только до «Готово»; «Изменить» возвращает её.
        if (плюс <= 0 || (состояние.готов && !ПИЛЮЛИ_ПОСЛЕ_ГОТОВО)) return;
        const у = создатьУзел('захват-пилюля', '+' + плюс);
        у.setAttribute('data-область', String(пил.область));
        поставитьМесто(у, пил.x, пил.y);
        показать(у, состояние.рисункиЕсть);
        слой.appendChild(у);
      });
    }

    function показатьСлой(ширина, выбранные) {
      состояние.слой = { ширина: ширина, выбранные: выбранные };
      return перерисоватьСлой();
    }

    // Слой перерисовывается и при «Готово» / «Изменить»: от этого зависят пилюли.
    function перерисоватьСлой() {
      if (!состояние.слой) return null;
      const раскладка = КартаВид.собратьРаскладку(состояние.партия,
        Object.assign({ ширина: состояние.слой.ширина }, состояние.слой.выбранные || {}));
      нарисоватьСлой(раскладка);
      return раскладка;
    }

    // ----- начало раунда и привязка кнопок -----

    // Новый раунд (или партия): свежий черновик, готовность снята. инфо — имена, готовы, боты, спят.
    function начатьРаунд(партия, мой, инфо, черновик) {
      состояние.партия = партия;
      состояние.мой = мой;
      состояние.инфо = Object.assign({ имена: {}, готовы: {}, боты: {}, спят: {} }, инфо || {});
      состояние.черновик = черновик ? копия(черновик) : { расстановка: {}, приказы: [] };
      состояние.история = [];
      состояние.готов = false;
      состояние.вопросОбОстатке = false;
      состояние.сообщение = '';
      закрытьПриказ();
      закрытьКарточку();
      обновитьВсё();
    }

    // Партия или готовность других поменялись (сеть, бот): перерисовать, черновик не трогать.
    function обновитьПартию(партия, инфо) {
      состояние.партия = партия;
      if (инфо) состояние.инфо = Object.assign(состояние.инфо, инфо);
      обновитьВсё();
    }

    function слушать(id, событие, действие) {
      const у = узел(id);
      if (у) у.addEventListener(событие, действие);
    }

    function привязатьКнопки() {
      слушать('захват-готово', 'click', нажатьГотовоИлиИзменить);
      слушать('захват-отменить', 'click', отменить);
      слушать('захват-приказ-минус', 'click', function () { добавитьВЛист(-1); });
      слушать('захват-приказ-плюс', 'click', function () { добавитьВЛист(1); });
      слушать('захват-приказ-ползунок', 'input', function () { задатьЧисло(узел('захват-приказ-ползунок').value); });
      слушать('захват-приказ-отдать', 'click', отдатьПриказ);
      слушать('захват-приказ-убрать', 'click', убратьПриказ);
      слушать('захват-приказ-отмена', 'click', закрытьПриказ);
      слушать('захват-карточка-закрыть', 'click', закрытьКарточку);
    }
    привязатьКнопки();

    return {
      начатьРаунд: начатьРаунд,
      обновитьПартию: обновитьПартию,
      показатьСлой: показатьСлой,
      поставитьВойска: поставитьВойска,
      отменить: отменить,
      нажатьГотово: нажатьГотово,
      поставитьОстатокИГотово: поставитьОстатокИГотово,
      отказатьсяОтВопроса: отказатьсяОтВопроса,
      изменить: изменить,
      открытьПриказ: открытьПриказ,
      задатьЧисло: задатьЧисло,
      отдатьПриказ: отдатьПриказ,
      убратьПриказ: убратьПриказ,
      закрытьПриказ: закрытьПриказ,
      открытьКарточку: открытьКарточку,
      закрытьКарточку: закрытьКарточку,
      черновик: function () { return копия(состояние.черновик); },
      готов: function () { return состояние.готов; }
    };
  }

  const ЗахватСтол = { создать: создать, СЛОВА: СЛОВА };

  if (typeof module !== 'undefined') module.exports = ЗахватСтол;
  if (typeof window !== 'undefined') window.ЗахватСтол = ЗахватСтол;
})();
