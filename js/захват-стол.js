    // Пилюля стоит серединой в точке x (сдвиг -50% делает оформление). У края карты половина пилюли
    // вылезла бы наружу и обрезалась, поэтому середину прижимаем в [полширины, ширина карты − полширины].
    // Ширину пилюли мерим узлом (offsetWidth): числа размеров в js не живут. Нет замера (проверки на node,
    // спрятанный узел) или нет слоя — прижима нет, пилюля стоит как раньше.
    function прижатьККарте(у, x) {
      const ширинаКарты = состояние.слой ? состояние.слой.ширина : 0;
      const ширинаПилюли = у.offsetWidth;
      if (!(ширинаКарты > 0) || !(ширинаПилюли > 0) || ширинаПилюли >= ширинаКарты) return x;
      return Math.min(ширинаКарты - ширинаПилюли / 2, Math.max(ширинаПилюли / 2, x));
    }

