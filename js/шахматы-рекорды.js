  window.ШахматыРекорды = {
    записатьПартию: записатьПартию,
    показать: показать,
    спрятать: спрятать,
    открыты: открыты,
    /** Нынешняя серия побед подряд — её называют в чате, когда хвастаются. */
    серия: function () { return серияПобед; }
  };
