/* =====================================================================
   Экран «Играть онлайн» — один на все сетевые игры сборника.

   У дурака (на странице есть узел «лобби-играть-онлайн») экран собирает
   сразу три сетевых входа (план-лобби-три-входа.md, Э4): «Найти игру» —
   автоподбор соперника, отдельный экран ожидания js/подбор-экран.js;
   список открытых столов с посадкой; «Создать игру» — три шага
   js/дурак-путь.js через готовую дверь window.ДуракЛобби.создатьИгру()
   (стол получается сразу открытым и с кодом другу, решения штаба №2–3);
   «Есть код? Войти» — единственный оставшийся после Э1 вход по коду,
   ведёт на уже существующий экран #экран-входа. У шашек и нард (узел
   «лобби-найти-игру») с 24.09 так же, как у дурака: список, всегда
   видимая «Создать игру» (стол создаётся сразу, без шагов настройки —
   настраивать у них нечего) и «Есть код? Войти». С 24.09
   (штаб/план-подбор-шашки-нарды.md, Э3) у шашек и нард появилась и
   «Найти игру» — тот же автоподбор, что у дурака, игру для очереди
   сервер узнаёт из тела запроса (js/сеть.js).

   Дверь наружу одна на все игры:
       window.ЭкранОткрытыхСтолов.открыть()
   У дурака её зовёт js/дурак-путь.js (карточка «лобби-играть-онлайн»),
   у шашек кнопку на карточке «лобби-найти-игру» вешает этот же файл сам.
   Файлы, которые рисуют сами лобби (js/game.js, js/дурак-путь.js,
   js/шашки-лобби.js), в этой задаче трогать нельзя — обработчик вешается
   снаружи, по имени узла, а не правкой чужого кода.

   Откуда берутся данные и как устроена посадка за стол — целиком
   в js/сеть.js (Сеть.открытыеСтолы, Сеть.сестьЗаСтол,
   Сеть.создатьОткрытыйСтол): этот файл только просит список и рисует его,
   второй сетевой дороги не прокладывает. «Создать игру» и «Есть код?»
   у дурака тоже не заводят свою сетевую дорогу — зовут готовые двери
   соседних файлов (window.ДуракЛобби.создатьИгру, скрытая кнопка
   «кнопка-войти-по-коду», которую уже слушает js/сеть.js).

   Разметку строим сами, как это делает js/рейтинг-экран.js: своих узлов
   на index.html и шашки.html для этого экрана нет, и мы вставляем его
   в общий контейнер #приложение теми же классами, что уже есть
   в style.css (.экран, .таблица, .таблица__строка, .кнопка, ...) —
   ни одного нового стиля из кода.

   Главное правило — как у соседних экранов: то, что приходит с сервера
   (имена сидящих за столом), вставляется ТОЛЬКО текстом (textContent),
   ни разу через innerHTML.
   ===================================================================== */

'use strict';

(function () {

  const ЭКРАН = 'экран-открытые-столы';
  const УЗЕЛ_СПИСОК = 'открытые-столы-список';
  const УЗЕЛ_СООБЩЕНИЕ = 'открытые-столы-сообщение';
  const КНОПКА_СОЗДАТЬ = 'открытые-столы-создать';
  const КНОПКА_НАЗАД = 'открытые-столы-назад';
  /* «Найти игру» — автоподбор соперника: у дурака и у шашек/нард (см.
     показатьКнопкуПодбора ниже); «Есть код?» — вход по коду, у всех игр. */
  const КНОПКА_ПОДБОР = 'открытые-столы-подбор';
  const КНОПКА_КОД = 'открытые-столы-код';
  /* Кроме дурака, автоподбор — у этих игр (штаб/план-подбор-шашки-
     нарды.md, штаб/план-подбор-четыре-игры.md) — сервер держит для них
     отдельные полки очереди. Морской бой и шахматы сюда не входят —
     подбора у них нет. */
  const ИГРЫ_С_ПОДБОРОМ = ['шашки', 'нарды', 'деберц', 'домино', 'катан', 'монополия'];

  /* Как часто обновляем список, пока экран открыт. Сервер сам не отвечает
     на эту дверь чаще раза в секунду (см. СПИСОК_НЕ_ЧАЩЕ в
     server/сервер.js) — четыре секунды с большим запасом: список решает
     не бой на реакцию, а выбор стола, торопиться сюда незачем. */
  const ОБНОВЛЯТЬ_КАЖДЫЕ = 4000;

  /* Сервер отвечает отказом 429, если один и тот же человек спрашивает
     список чаще раза в секунду (см. СПИСОК_НЕ_ЧАЩЕ в server/сервер.js).
     Наш код такой отказ разбирает спокойно, но браузер всё равно печатает
     в консоль свою красную строку про неудачный запрос — это делает сам
     Chromium, а не наш JS, и никак изнутри JS это не погасить. Единственный
     способ — не спрашивать чаще: быстрый «Назад» и тут же новое открытие
     экрана (двойной тап) иначе стучались бы в сервер дважды подряд. */
  const РЕЖЕ_ЧЕМ_РАЗ_В = 1100;

  let таймер = null;
  let запросИдёт = false;
  let последнийЗапросВремя = 0;
  let откудаПришли = 'экран-лобби';
  /* Растёт при каждом открытии и закрытии экрана. По нему опоздавший ответ
     сервера узнаётся и выбрасывается: без этого список мог бы нарисоваться
     поверх уже закрытого экрана или поверх свежего открытия того же. */
  let поколение = 0;

  function узел(id) {
    return document.getElementById(id);
  }

  /* -------------------------------------------------------------------
     Экран и кнопки
     ------------------------------------------------------------------- */

  /** Показать экран. Мост из js/game.js (или шашечный аналог) умеет
      заодно погасить ленту и панель знаков — своей переключалкой это
      не повторить, поэтому зовём его первым. Моста нет — переключаем
      классы сами, простым способом (тот же приём, что в js/сеть.js). */
  function показатьЭкран(id) {
    if (window.ИграПоСети && typeof window.ИграПоСети.экран === 'function') {
      window.ИграПоСети.экран(id);
      return;
    }
    for (const экран of document.querySelectorAll('.экран')) {
      экран.classList.toggle('экран--виден', экран.id === id);
    }
  }

  function текущийЭкран() {
    const открытый = document.querySelector('.экран.экран--виден');
    return (открытый && открытый.id) || 'экран-лобби';
  }

  /* Системная стрелка Telegram делает тот же шаг, что и кнопка «Назад»
     на экране (правило сборника). Дверь общая (js/telegram.js), нет
     Telegram — не страшно, на экране есть обычная кнопка. */
  function попытатьсяПривязатьСтрелку(действие) {
    try {
      if (window.Телеграм && typeof window.Телеграм.показатьСтрелку === 'function') {
        window.Телеграм.показатьСтрелку(действие);
      }
    } catch (сбой) {
      /* нет Telegram — ничего страшного */
    }
  }

  /* -------------------------------------------------------------------
     Своя разметка (index.html и шашки.html её не пишут)
     ------------------------------------------------------------------- */

  /** Полный онлайн-вход: Дурак или игра со своим мастером создания.
      Автоподбор остаётся только у Дурака; список и вход по коду общие. */
  function режимДурака() {
    return Boolean(узел('лобби-играть-онлайн') || window.НастройкиЭкранаОнлайн);
  }

  /** Показывать ли «Найти игру»: у дурака (свой узел «лобби-играть-
      онлайн») и у игр из списка ИГРЫ_С_ПОДБОРОМ — независимо от того,
      есть ли у игры свой мастер «Создать игру» (window.НастройкиЭкрана-
      Онлайн, деберц/домино/катан/монополия и морской бой): подбор и
      создание стола — разные двери, одна не решает про другую (штаб/
      план-подбор-четыре-игры.md, Э3). У морского боя и шахмат — своей
      полки очереди на сервере нет, поэтому их в списке нет и кнопки нет. */
  function показатьКнопкуПодбора() {
    const играСтраницы = String(window.ИграСтраницы || '').trim();
    const свояОчередь = ИГРЫ_С_ПОДБОРОМ.indexOf(играСтраницы) !== -1;
    return Boolean(узел('лобби-играть-онлайн')) || свояОчередь;
  }

  function хозяинЭкранов() {
    const хозяин = document.getElementById('приложение') || document.body;
    return (хозяин && typeof хозяин.appendChild === 'function') ? хозяин : null;
  }

  function заголовокЭкрана(текст) {
    const н = document.createElement('h2');
    н.className = 'заголовок';
    н.textContent = текст;
    return н;
  }

  function контейнер(id, класс) {
    const н = document.createElement('div');
    if (id) н.id = id;
    if (класс) н.className = класс;
    return н;
  }

  function абзацСУзлом(id, класс) {
    const н = document.createElement('p');
    н.id = id;
    н.className = класс;
    return н;
  }

  function кнопкаЭл(id, текст, класс, действие) {
    const н = document.createElement('button');
    н.type = 'button';
    н.id = id;
    н.className = класс;
    н.textContent = текст;
    if (действие) н.addEventListener('click', действие);
    return н;
  }

  function построитьЭкран() {
    const хозяин = хозяинЭкранов();
    if (!хозяин) return null;

    const дурак = режимДурака();
    const секция = document.createElement('section');
    секция.id = ЭКРАН;
    секция.className = 'экран';

    /* Заголовок один у всех игр — как у дурака и как карточка в лобби
       (решение штаба 24.09). */
    секция.appendChild(заголовокЭкрана('Играть онлайн'));

    if (показатьКнопкуПодбора()) {
      /* «Найти игру» тут — автоподбор соперника (решение штаба №1,
         план-лобби-три-входа.md): список ниже — это открытые столы,
         а сам подбор ведёт отдельный экран ожидания js/подбор-экран.js. */
      секция.appendChild(кнопкаЭл(КНОПКА_ПОДБОР, 'Найти игру',
        'кнопка кнопка--главная', нажалиНайтиИгру));
    }

    /* Сообщение общее на все случаи: «нет Telegram», «сервер не отвечает»,
       «пусто», «место заняли» — всегда одна и та же строка над списком. */
    секция.appendChild(абзацСУзлом(УЗЕЛ_СООБЩЕНИЕ, 'таблица__пусто скрыт'));
    секция.appendChild(контейнер(УЗЕЛ_СПИСОК, 'таблица'));
    /* «Создать игру» — одна подпись и одно место у всех игр (эталон —
       дурак, сверка штаба 24.09). Разница только в том, что происходит
       по нажатию: у дурака и игр со своим мастером — шаги настройки,
       у шашек и нард настраивать нечего — стол создаётся сразу. */
    секция.appendChild(кнопкаЭл(КНОПКА_СОЗДАТЬ, 'Создать игру',
      'кнопка кнопка--главная',
      дурак ? нажалиСоздатьИгру : нажалиСоздать));

    /* «Есть код?» — единственный вход по коду у всех игр, и живёт он здесь,
       а не строкой в лобби (как у дурака): полный экран ввода
       (#экран-входа) уже собран и работает сам — зовём его готовую
       скрытую дверь, свою в сеть не заводим. */
    секция.appendChild(кнопкаЭл(КНОПКА_КОД, 'Есть код? Войти',
      'кнопка кнопка--мелкая', нажалиЕстьКод));

    секция.appendChild(кнопкаЭл(КНОПКА_НАЗАД, 'Назад', 'кнопка', назад));

    хозяин.appendChild(секция);
    return секция;
  }

  function убедитьсяЧтоЭкранЕсть() {
    return узел(ЭКРАН) || построитьЭкран();
  }

  /* -------------------------------------------------------------------
     Рисование списка
     ------------------------------------------------------------------- */

  function очистить(место) {
    if (!место) return;
    while (место.firstChild) место.removeChild(место.firstChild);
  }

  function ячейка(текст, класс) {
    const элемент = document.createElement('span');
    элемент.className = класс;
    элемент.textContent = текст;
    return элемент;
  }

  /** Сколько стол уже ждёт — по-человечески, без «0 секунд» и «1 минут». */
  function словамиЖдёт(секунд) {
    const с = Number.isFinite(секунд) ? Math.max(0, Math.round(секунд)) : 0;
    if (с < 60) return 'ждёт меньше минуты';
    const минут = Math.round(с / 60);
    const последняя = минут % 10;
    const двеПоследние = минут % 100;
    let слово = 'минут';
    if (!(двеПоследние >= 11 && двеПоследние <= 14)) {
      if (последняя === 1) слово = 'минуту';
      else if (последняя >= 2 && последняя <= 4) слово = 'минуты';
    }
    return 'ждёт ' + минут + ' ' + слово;
  }

  /** Кто уже сидит — имена через запятую; за столом пока никого нет. */
  function словамиИгроки(имена) {
    const список = Array.isArray(имена)
      ? имена.filter(function (и) { return typeof и === 'string' && и; })
      : [];
    return список.length ? список.join(', ') : 'за столом пока никого';
  }

  /** Одна строка списка — общими классами таблицы (см. style.css, «.таблица__строка»). */
  function строкаСтола(стол, моёПоколение) {
    const строка = document.createElement('div');
    строка.className = 'таблица__строка';

    ячейкиСтола(строка, стол);

    const кнопка = document.createElement('button');
    кнопка.type = 'button';
    кнопка.className = 'кнопка кнопка--мелкая';
    кнопка.textContent = 'Сесть';
    кнопка.addEventListener('click', function () {
      нажалиСесть(стол.ключ, кнопка, моёПоколение);
    });
    строка.appendChild(кнопка);

    return строка;
  }

  /** Ячейки строки (кроме кнопки «Сесть») — вынесены отдельно ради читаемости. */
  function ячейкиСтола(строка, стол) {
    строка.appendChild(ячейка(стол.занято + '/' + стол.мест, 'таблица__место'));
    строка.appendChild(ячейка(словамиИгроки(стол.игроки), 'таблица__очки'));
    строка.appendChild(ячейка(словамиЖдёт(стол.ждётСекунд), 'таблица__дата'));
    /* Правила стола («Переводной, парами») приходят только для дурака
       (см. правилаСтола в server/комнаты.js) — у шашек и прочих игр
       строка пустая, и лишнюю ячейку тогда не рисуем вовсе. */
    if (стол.правилаСтола) {
      строка.appendChild(ячейка(стол.правилаСтола, 'таблица__сложность'));
    }
  }

  function показатьСообщение(текст) {
    const место = узел(УЗЕЛ_СООБЩЕНИЕ);
    if (!место) return;
    место.textContent = текст || '';
    место.classList.toggle('скрыт', !текст);
  }

  function показатьКнопкуСоздать() {
    const кнопка = узел(КНОПКА_СОЗДАТЬ);
    if (!кнопка) return;
    /* «Создать игру» — не аварийный выход из пустого списка, а
       равноправный вход (решение штаба №3 для дурака, с 24.09 — у всех
       игр): видна всегда, независимо от того, пуст список или нет. */
    кнопка.classList.remove('скрыт');
    /* Зовётся при каждом открытии экрана. Если прошлое «Создаём…» ушло
       со старого открытия (нажали «Создать», потом «Назад»), его поздний
       ответ кнопку уже не тронет (другое поколение) — возвращаем её
       в рабочий вид здесь, иначе она навсегда осталась бы выключенной.
       От двойного нажатия внутри одного открытия защищает disabled
       в нажалиСоздать, а повтор после переоткрытия отсечёт js/сеть.js
       («Уже создаём стол — подождите»). */
    кнопка.disabled = false;
    кнопка.textContent = 'Создать игру';
  }

  /**
   * Показать готовый ответ сервера — единственное место, где список рисуется.
   * Порядок проверок важен: сперва «нет Telegram» (её отдаёт уже
   * Сеть.открытыеСтолы), потом любая другая беда, потом пусто-или-список.
   */
  function нарисовать(ответ) {
    const список = узел(УЗЕЛ_СПИСОК);
    if (!список) return;
    очистить(список);

    if (ответ.узналиВас === false) {
      показатьСообщение(ответ.причина || 'Найти игру можно только в Telegram.');
      return;
    }
    if (!ответ.ок) {
      показатьСообщение(ответ.причина || 'Список сейчас не открывается — сервер не отвечает.');
      return;
    }
    if (!ответ.столы.length) {
      показатьСообщение('Пока никто не открыл стол.');
      return;
    }
    показатьСообщение('');
    for (const стол of ответ.столы) список.appendChild(строкаСтола(стол, поколение));
  }

  /* -------------------------------------------------------------------
     Действия: обновление, посадка, создание, назад
     ------------------------------------------------------------------- */

  function обновить() {
    if (!window.Сеть || typeof window.Сеть.открытыеСтолы !== 'function') return;
    if (запросИдёт) return;   // предыдущий ответ ещё в пути — второй не шлём
    /* Слишком рано после прошлого запроса — сервер всё равно откажет
       (см. РЕЖЕ_ЧЕМ_РАЗ_В выше). Следующий тик таймера подойдёт сам. */
    if (Date.now() - последнийЗапросВремя < РЕЖЕ_ЧЕМ_РАЗ_В) return;
    запросИдёт = true;
    последнийЗапросВремя = Date.now();
    const моё = поколение;
    window.Сеть.открытыеСтолы().then(function (ответ) {
      запросИдёт = false;
      if (моё !== поколение) return;   // экран уже закрыт или открыт заново
      нарисовать(ответ || { ок: false, узналиВас: false, столы: [], причина: '' });
    });
  }

  function запуститьОбновление() {
    остановитьОбновление();
    обновить();
    таймер = setInterval(обновить, ОБНОВЛЯТЬ_КАЖДЫЕ);
  }

  function остановитьОбновление() {
    if (таймер !== null) {
      clearInterval(таймер);
      таймер = null;
    }
  }

  /** Нажали «Сесть» на конкретной строке списка. */
  function нажалиСесть(ключ, кнопка, моёПоколение) {
    if (!window.Сеть || typeof window.Сеть.сестьЗаСтол !== 'function') return;
    кнопка.disabled = true;
    кнопка.textContent = 'Садимся…';
    window.Сеть.сестьЗаСтол(ключ).then(function (итог) {
      if (моёПоколение !== поколение) return;   // экран уже не тот
      if (итог && итог.ок) {
        остановитьОбновление();   // Сеть.сестьЗаСтол уже повела в комнату
        return;
      }
      /* Не вышло — стол заняли, закрыли или ключ протух. Честная строка
         и тут же новый список: тот же стол в нём уже не появится. */
      показатьСообщение((итог && итог.причина) || 'Сесть за стол не вышло.');
      обновить();
    });
  }

  /** Нажали «Создать игру» у шашек и нард: шагов настройки нет — стол
      сразу открытый и с кодом другу (тот же исход, что у дурака), дорогу
      в комнату ведёт js/сеть.js. */
  function нажалиСоздать() {
    if (!window.Сеть || typeof window.Сеть.создатьОткрытыйСтол !== 'function') return;
    const кнопка = узел(КНОПКА_СОЗДАТЬ);
    if (кнопка) {
      кнопка.disabled = true;
      кнопка.textContent = 'Создаём…';
    }
    const моё = поколение;
    window.Сеть.создатьОткрытыйСтол().then(function (итог) {
      if (моё !== поколение) return;
      if (кнопка) {
        кнопка.disabled = false;
        кнопка.textContent = 'Создать игру';
      }
      if (итог && итог.ок) {
        остановитьОбновление();   // Сеть.создатьОткрытыйСтол уже повела в комнату
        return;
      }
      показатьСообщение((итог && итог.причина) || 'Стол создать не вышло.');
    });
  }

  /** «Найти игру» (дурак, шашки, нарды) — автоподбор соперника, отдельный
      экран ожидания (js/подбор-экран.js). Тот же приём, что и у этого
      файла: экран подбора сам запомнит, что пришли отсюда, и сам сюда же
      вернёт по «Назад»/отмене — переключать что-то здесь не нужно. */
  function нажалиНайтиИгру() {
    if (window.ЭкранПодбора && typeof window.ЭкранПодбора.открыть === 'function') {
      window.ЭкранПодбора.открыть();
    }
  }

  /** «Создать игру» (дурак) — три шага js/дурак-путь.js через готовую
      дверь window.ДуракЛобби.создатьИгру() (те же шаги, что раньше
      открывала карточка «Пригласить друзей»; решения штаба №2–3:
      стол получается сразу открытым и с кодом другу, отдельной кнопки
      «Создать открытый стол» больше нет). Двери нет (старая страница
      без js/game.js/дурак-путь.js) — тихо ничего не делаем, список
      остаётся на месте, как и у соседних дверей этого файла. */
  function нажалиСоздатьИгру() {
    const мастер = window.НастройкиЭкранаОнлайн || window.ДуракЛобби;
    if (!мастер || typeof мастер.создатьИгру !== 'function') return;
    const кнопка = узел(КНОПКА_СОЗДАТЬ);
    if (кнопка) {
      кнопка.disabled = true;
      кнопка.textContent = 'Создаём…';
    }
    остановитьОбновление();
    поколение++;   // уходим со списка не через «назад» — как при «Сесть»
    мастер.создатьИгру();
    /* Переход тут не через промис (в отличие от соседней шашечной
       кнопки), а синхронные три шага js/дурак-путь.js — они либо уже
       сменили экран к этой строке, либо дверь не сработала и мы всё ещё
       здесь. В обоих случаях кнопку сразу возвращаем в исходный вид:
       если экран сменился, эта секция скрыта и никто не заметит; если
       не сменился — кнопка не должна навсегда остаться «Создаём…». */
    if (кнопка) {
      кнопка.disabled = false;
      кнопка.textContent = 'Создать игру';
    }
  }

  /** «Есть код? Войти» (все игры) — единственный вход по коду, оставшийся
      после Э1. Полный экран ввода (#экран-входа, поле-кода, кнопка-
      войти, сообщение-входа) уже целиком собран и обслуживается
      js/сеть.js сам — своей двери в сеть не заводим, а нажимаем ту же
      скрытую кнопку, которой раньше касалась карточка «лобби-код»
      (тот же приём, что «нажатьКнопкуСети» в js/game.js). */
  function нажалиЕстьКод() {
    const кнопка = узел('кнопка-войти-по-коду');
    if (!кнопка) return;
    остановитьОбновление();
    поколение++;   // уходим со списка не через «назад»
    кнопка.click();
  }

  function назад() {
    остановитьОбновление();
    поколение++;   // всё, что ещё летит с сервера, теперь устарело
    показатьЭкран(откудаПришли);
  }

  /** Открыть экран «Играть онлайн» (у всех игр он называется так).
      Одна дверь наружу. */
  function открыть() {
    const было = текущийЭкран();
    if (было !== ЭКРАН) откудаПришли = было;
    убедитьсяЧтоЭкранЕсть();
    показатьСообщение('');
    показатьКнопкуСоздать();
    очистить(узел(УЗЕЛ_СПИСОК));
    показатьЭкран(ЭКРАН);
    попытатьсяПривязатьСтрелку(назад);
    поколение++;
    запуститьОбновление();
  }

  /* -------------------------------------------------------------------
     Подключение к карточке лобби
     ------------------------------------------------------------------- */

  function подключитьКнопкуЛобби() {
    /* У дурака карточку «лобби-играть-онлайн» на эту же дверь подписывает
       js/дурак-путь.js сам (id «лобби-онлайн» после Э1 на странице дурака
       больше нет — второй обработчик на ту же кнопку заводить незачем).
       У шашек своя карточка «лобби-найти-игру» остаётся прежней. */
    const кнопка = узел('лобби-найти-игру');
    if (кнопка) кнопка.addEventListener('click', открыть);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', подключитьКнопкуЛобби);
  } else {
    подключитьКнопкуЛобби();
  }

  window.ЭкранОткрытыхСтолов = { открыть: открыть };

})();
