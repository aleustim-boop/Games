/**
 * Нижняя полоса вкладок — общая для всех «домашних» экранов сборника
 * (витрина, лобби каждой игры), но не для самой партии: во время игры
 * полосы на странице просто нет (её сюда не кладут).
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Раньше разметка полосы была написана в index.html
 * дважды — на витрине и в лобби дурака, — со своими копиями одних и тех
 * же значков-SVG. Из-за этого подписи и порядок вкладок легко могли
 * разойтись между играми, а владелец просил ровно обратное: «Лобби ·
 * Рейтинг · Профиль» одинаково везде. Теперь список вкладок и значки
 * живут в одном месте, а страница просто просит нужный набор:
 *   <nav class="нижние-вкладки" data-вкладки="витрина"></nav>
 *
 * УСТРОЙСТВО. «вкладкиНабора(имя)» — чистая функция без DOM: набор ->
 * список описаний кнопок. Её же используют для проверки (в Node, без
 * браузера) в скрипте штаба. Всё остальное — обвязка вокруг неё: рисует
 * кнопки в <nav> и вешает клик там, где своей двери у вкладки нет.
 *
 * ПЕРЕХОДЫ НЕ ЗАВОДЯТСЯ ЗАНОВО. У вкладок «Рейтинг» и «Профиль» в лобби
 * дурака id узлов те же, что были в разметке раньше («лобби-вкладка-
 * рейтинг», «лобби-вкладка-профиль») — их уже слушают js/game.js и
 * js/дурак-путь.js, эта дверь не трогается. На витрине «Рейтинг» держит
 * прежний id «кнопка-вкладка-профиль» (под ним её слушает js/game.js —
 * это старое имя от прежней подписи «Профиль», переименовывать саму
 * дверь в этом заходе не входило в план). А «Профиль» на витрине —
 * новая кнопка «кнопка-вкладка-мой-счёт»: она не заводит вторую дверь
 * к «Как я играю», а просто нажимает уже существующую скрытую кнопку
 * «кнопка-мой-счёт» (та стоит на экране рекордов и там же и остаётся).
 *
 * ПОРЯДОК ПОДКЛЮЧЕНИЯ В index.html ВАЖЕН: этот файл должен выполниться
 * РАНЬШЕ js/game.js. Скрипты внизу страницы — обычные, без defer, и
 * выполняются по очереди сразу при разборе страницы; js/game.js уже на
 * этом же проходе ищет кнопки «кнопка-вкладка-профиль», «лобби-вкладка-
 * рейтинг» и «лобби-вкладка-профиль» по id. Если их ещё нет в DOM —
 * js/game.js тихо ничего не найдёт, и вкладки останутся без дела.
 */
(function () {
  'use strict';

  /* Значки — те же самые SVG, что раньше были вписаны прямо в index.html.
     Новых не рисуем: просто переносим готовую разметку сюда, в одно место. */
  const ЗНАЧОК_ИГРЫ =
    '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false"><path d="M8 5h8c2 0 3 1 3.5 3l2 10c.4 2-1.7 3-3 1l-3-3h-7l-3 3c-1.3 2-3.4 1-3-1l2-10C5 6 6 5 8 5Z"/><path d="M6.5 10h5M9 7.5v5"/><circle cx="16" cy="10" r=".9" fill="currentColor" stroke="none"/></svg>';
  const ЗНАЧОК_ЛОББИ =
    '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false"><path d="m2 10 10-9 10 9v12h-7v-8H9v8H2Z" fill="currentColor" stroke="none"/></svg>';
  const ЗНАЧОК_РЕЙТИНГ =
    '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false"><rect x="2" y="13" width="5" height="10" rx="1" fill="currentColor" stroke="none"/><rect x="10" y="7" width="5" height="16" rx="1" fill="currentColor" stroke="none"/><rect x="18" y="1" width="5" height="22" rx="1" fill="currentColor" stroke="none"/></svg>';
  const ЗНАЧОК_ПРОФИЛЬ_ВИТРИНА =
    '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false"><circle cx="12" cy="12" r="10"/><circle cx="12" cy="9" r="3.5"/><path d="M5 19c1-6 13-6 14 0"/></svg>';
  const ЗНАЧОК_ПРОФИЛЬ_ЛОББИ =
    '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false"><circle cx="12" cy="6" r="4" fill="currentColor" stroke="none"/><path d="M4 22v-3c0-9 16-9 16 0v3Z" fill="currentColor" stroke="none"/></svg>';

  /**
   * Наборы вкладок по имени. Ничего мёртвого здесь не заводим: у каждой
   * вкладки либо есть свой id (за него уже отвечает другой файл), либо
   * своё «действие» (эта кнопка сама нажимает чужую дверь).
   *   id       — id кнопки в разметке; null — у активной вкладки своей
   *              двери нет, потому что она и так на этом самом экране;
   *   действие — имя обработчика из ДЕЙСТВИЯ, когда своей двери с id нет.
   */
  const НАБОРЫ = {
    // Витрина: список игр. Активна первая вкладка — сама витрина.
    'витрина': [
      { id: null, подпись: 'Игры', значок: ЗНАЧОК_ИГРЫ, активна: true },
      { id: 'кнопка-вкладка-профиль', подпись: 'Рейтинг', значок: ЗНАЧОК_РЕЙТИНГ, активна: false },
      { id: 'кнопка-вкладка-мой-счёт', подпись: 'Профиль', значок: ЗНАЧОК_ПРОФИЛЬ_ВИТРИНА, активна: false, действие: 'мой-счёт' }
    ],
    // Лобби дурака: активна первая вкладка — само лобби.
    'лобби-дурака': [
      { id: null, подпись: 'Лобби', значок: ЗНАЧОК_ЛОББИ, активна: true },
      { id: 'лобби-вкладка-рейтинг', подпись: 'Рейтинг', значок: ЗНАЧОК_РЕЙТИНГ, активна: false },
      { id: 'лобби-вкладка-профиль', подпись: 'Профиль', значок: ЗНАЧОК_ПРОФИЛЬ_ЛОББИ, активна: false }
    ]
  };

  /**
   * Список вкладок набора — чистые данные, без DOM. Работает и в браузере,
   * и в Node (в проверке штаба). Неизвестное имя даёт пустой список, а не
   * ошибку — вызывающая сторона сама решает, ругаться или нет.
   */
  function вкладкиНабора(имя) {
    const список = НАБОРЫ[имя];
    if (!список) return [];
    // Отдаём копии, а не сами объекты набора: снаружи их можно менять,
    // не портя исходный список для следующего запроса.
    return список.map(function (вкладка) {
      return Object.assign({}, вкладка);
    });
  }

  /** Строка HTML одной кнопки-вкладки по её описанию. */
  function кнопкаHTML(вкладка) {
    const классы = 'нижняя-вкладка' + (вкладка.активна ? ' нижняя-вкладка--активна' : '');
    const атрибутId = вкладка.id ? ' id="' + вкладка.id + '"' : '';
    const атрибутТекущая = вкладка.активна ? ' aria-current="page"' : '';
    const атрибутДействие = вкладка.действие ? ' data-нижняя-вкладка-действие="' + вкладка.действие + '"' : '';
    return '<button type="button" class="' + классы + '"' + атрибутId + атрибутТекущая + атрибутДействие + '>' +
      '<span class="нижняя-вкладка__значок">' + вкладка.значок + '</span>' +
      '<span class="нижняя-вкладка__подпись">' + вкладка.подпись + '</span>' +
      '</button>';
  }

  /* Двери для вкладок без своей кнопки: нажимают уже существующую кнопку
     в другом месте страницы, а не заводят вторую дорогу к тому же экрану. */
  const ДЕЙСТВИЯ = {
    'мой-счёт': function () {
      const кнопка = document.getElementById('кнопка-мой-счёт');
      if (кнопка) кнопка.click();
    }
  };

  /** Заполнить один <nav data-вкладки="имя набора"> его кнопками. */
  function заполнитьПолосу(nav) {
    const имя = nav.getAttribute('data-вкладки');
    const вкладки = вкладкиНабора(имя);
    if (!вкладки.length) {
      console.warn('Нижние вкладки: неизвестный набор «' + имя + '», полоса останется пустой.');
      return;
    }
    nav.innerHTML = вкладки.map(кнопкаHTML).join('');
    вкладки.forEach(function (вкладка) {
      if (!вкладка.действие) return;
      const дело = ДЕЙСТВИЯ[вкладка.действие];
      if (!дело) return;
      const узел = nav.querySelector('[data-нижняя-вкладка-действие="' + вкладка.действие + '"]');
      if (узел) узел.addEventListener('click', дело);
    });
  }

  // В браузере — сразу заполняем все полосы, какие есть на странице.
  // Скрипт подключён обычным тегом (без defer) раньше js/game.js, поэтому
  // к его запуску разметка уже разобрана, а игра ещё не искала эти кнопки.
  if (typeof document !== 'undefined') {
    const полосы = document.querySelectorAll('.нижние-вкладки[data-вкладки]');
    for (let i = 0; i < полосы.length; i++) заполнитьПолосу(полосы[i]);
  }

  // Наружу — чистая функция набора (для проверки в Node) и сборка полосы.
  const НижниеВкладки = { вкладкиНабора: вкладкиНабора, кнопкаHTML: кнопкаHTML };
  if (typeof module !== 'undefined' && module.exports) module.exports = НижниеВкладки;
  if (typeof window !== 'undefined') window.НижниеВкладки = НижниеВкладки;
})();
