/**
 * Лист «⋯» стола — общий для всех игр сборника.
 *
 * ЗАЧЕМ ОБЩИЙ ФАЙЛ. Один и тот же лист был написан дважды: в js/game.js
 * (дурак — «открытьЛистИгры», «закрытьЛистИгры», «изЛистаИгры»,
 * «освежитьКнопкуНастроек») и заново в js/нарды-экран.js. Копии уже
 * разошлись мелочами, а впереди ещё шашки и шахматы — было бы уже
 * четыре копии одного и того же (см. штаб/план-единый-стиль.md, Э1).
 * Теперь устройство живёт в одном месте, а игра лишь называет свои
 * «двери» — что должна сделать каждая строка листа.
 *
 * УСТРОЙСТВО, как у js/нижние-вкладки.js (сделан раньше, тот же приём):
 *   «строкиЛиста(двери)» — чистая функция без DOM: набор дверей ->
 *   список строк, которые сейчас должны быть видны, в фиксированном
 *   порядке. Она же используется для проверки в Node, без браузера
 *   (штаб/…). Остальное — обвязка: открытие, закрытие, привязка кнопок
 *   к уже готовой разметке в html каждой игры (сам html не строит —
 *   разметку листа рисует страница, здесь только показ/скрытие строк
 *   классом «скрыт» и поведение).
 *
 * ДВЕРИ, КОТОРЫЕ ЖДЁТ МОДУЛЬ. Игра передаёт объект «двери» — тех
 * строк, которых у неё нет вовсе, в объекте быть не должно (тогда
 * строки не будет, даже если кнопка для неё есть в разметке):
 *
 *   вМеню      { действие, видна }     — «видна()», если задана: идёт
 *                ли сейчас партия. Не задана — строка видна всегда
 *                (так у нард, которых Э1 ещё не учит прятать «В меню»).
 *   завершить  { действие, видна, текст, пауза, продолжить } — необязательная
 *                дверь (штаб/план-выход-из-партии.md, Э1): пока идёт партия,
 *                занимает то же место в листе, что и «вМеню» — вместо
 *                «В меню» строка называется «Завершить партию» и ведёт не
 *                сразу в дверь, а в общее подтверждение.
 *                  видна()      — партия идёт сейчас (true — показываем
 *                                 «Завершить партию» вместо «В меню»).
 *                  действие()   — игрок подтвердил «Завершить» в плашке.
 *                  текст        — строка или функция без аргументов,
 *                                 отдающая строку последствия для игрока:
 *                                 у каждого режима игры оно своё («Партия
 *                                 прервётся, в рекорды не попадёт» / «Засчи-
 *                                 тается поражение, сопернику — победа» и т.п.).
 *                  пауза()      — необязательно: плашка подтверждения
 *                                 открылась (поставить партию на паузу).
 *                  продолжить() — необязательно: игрок нажал «Вернуться
 *                                 к игре» (снять паузу). При «Завершить»
 *                                 не вызывается — партия и так кончается.
 *                Дверь не передана или видна() не идёт — всё как раньше:
 *                строка «В меню» из двери «вМеню» без подтверждения
 *                (обратная совместимость со старыми играми).
 *   какИграть  { действие }
 *   звук       { действие, состояние } — «состояние()» -> 'вкл'/'выкл',
 *                показывается в строке, если в разметке есть узел
 *                «<id-кнопки>-состояние» заменён на «лист-игры-звук-
 *                состояние» (см. ПОРЯДОК ниже — так же, как у дурака).
 *   вибрация   { действие, доступна, состояние } — «доступна()»: нет
 *                функции или вернула false — строки нет вовсе (телефон
 *                вибрацию не умеет).
 *   оформление { действие }
 *   рекорды    { действие }
 *
 * Порядок строк ФИКСИРОВАН и совпадает с нынешним листом дурака:
 * В меню, Как играть, Звук, Вибрация, Оформление, Рекорды.
 *
 * ЧЕГО МОДУЛЬ НЕ ДЕЛАЕТ. Не строит разметку листа (id узлов те же, что
 * были всегда — на них держится style.css и старые проверки), не решает
 * сам, на каких экранах он уместен для «Настроек» Telegram — это говорит
 * игра через «экраныСЛистом» при подключении, потому что имена экранов
 * у каждой игры свои.
 */
(function () {
  'use strict';

  /* Порядок и id строк — те же, что в разметке дурака (index.html) и
     нард (нарды.html): переименовывать нельзя, за них держится style.css. */
  const ПОРЯДОК = [
    { ключ: 'вМеню', id: 'кнопка-лист-игры-меню' },
    { ключ: 'какИграть', id: 'кнопка-лист-игры-правила' },
    { ключ: 'звук', id: 'кнопка-лист-игры-звук', idСостояния: 'лист-игры-звук-состояние' },
    { ключ: 'вибрация', id: 'кнопка-лист-игры-вибрация', idСостояния: 'лист-игры-вибрация-состояние' },
    { ключ: 'оформление', id: 'кнопка-лист-игры-оформление' },
    { ключ: 'рекорды', id: 'кнопка-лист-игры-рекорды' }
  ];

  /* Строки-переключатели: клик их не закрывает — человеку должно быть
     видно, как слово «вкл» сменилось на «выкл», как у листа «Ещё» витрины. */
  const ПЕРЕКЛЮЧАТЕЛИ = { звук: true, вибрация: true };

  /* Подпись строки на месте «вМеню» — та же кнопка в разметке (id
     «кнопка-лист-игры-меню»), но во время партии называется иначе. */
  const ТЕКСТ_В_МЕНЮ = 'В меню';
  const ТЕКСТ_ЗАВЕРШИТЬ = 'Завершить партию';

  /* Плашка общего подтверждения «Завершить партию?» — id и классы для
     оформителя (штаб/план-выход-из-партии.md, Э2): .плашка-завершить
     (корень, прячется классом «скрыт», как лист), .плашка-завершить__фон,
     .плашка-завершить__окно, .плашка-завершить__заголовок,
     .плашка-завершить__текст (последствие от игры), .плашка-завершить__кнопки,
     кнопка «Завершить» — .кнопка.кнопка--опасная, «Вернуться к игре» —
     .кнопка.кнопка--главная. */
  const ID_ПЛАШКИ = 'плашка-завершить';

  /**
   * Какая дверь сейчас должна отвечать за строку на месте «В меню»:
   * { ключ: 'завершить', дверь } — партия идёт, дверь «завершить» передана;
   * { ключ: 'вМеню', дверь } — обычное «В меню» (партия не идёт или двери
   * «завершить» вовсе нет — старые игры, которых Э1 не касается);
   * null — строки на этом месте не должно быть вовсе.
   * Чистая функция без DOM — совпадает с логикой строкиЛиста().
   */
  function активнаяДверьМеню(двери) {
    const завершить = двери.завершить;
    if (завершить && typeof завершить.видна === 'function' && завершить.видна()) {
      return { ключ: 'завершить', дверь: завершить };
    }
    const вМеню = двери.вМеню;
    if (!вМеню) return null;
    if (typeof вМеню.видна === 'function' && !вМеню.видна()) return null;
    return { ключ: 'вМеню', дверь: вМеню };
  }

  /**
   * Список строк, которые сейчас видны — чистые данные, без DOM.
   * Работает и в браузере, и в Node (для проверки без браузера).
   * Дверь не передана — строки нет вовсе; «вМеню»/«завершить» и «вибрация»
   * решают видимость ещё и по своим полям (см. пояснение в шапке файла).
   */
  function строкиЛиста(двери) {
    двери = двери || {};
    const строки = [];
    ПОРЯДОК.forEach(function (описание) {
      if (описание.ключ === 'вМеню') {
        const активная = активнаяДверьМеню(двери);
        if (активная) строки.push({ ключ: активная.ключ, id: описание.id });
        return;
      }
      const дверь = двери[описание.ключ];
      if (!дверь) return;
      if (описание.ключ === 'вибрация') {
        const доступна = typeof дверь.доступна === 'function' && дверь.доступна();
        if (!доступна) return;
      }
      строки.push({ ключ: описание.ключ, id: описание.id });
    });
    return строки;
  }

  /** Показать/спрятать строки в уже готовой разметке и обновить текст «вкл/выкл». */
  function освежитьВидимость(двери) {
    // Ключ строки на месте «В меню» бывает разным («вМеню» или «завершить»),
    // а узел в разметке — один и тот же, поэтому сверяемся по id, не по ключу.
    const строкиПоId = Object.create(null);
    строкиЛиста(двери).forEach(function (с) { строкиПоId[с.id] = с; });
    ПОРЯДОК.forEach(function (описание) {
      const узел = document.getElementById(описание.id);
      if (!узел) return;   // в разметке этой игры такой строки нет вовсе — тихо
      const строка = строкиПоId[описание.id];
      узел.classList.toggle('скрыт', !строка);
      if (описание.ключ === 'вМеню') {
        // Подпись переключается между «В меню» и «Завершить партию» —
        // та же кнопка, текст живёт внутри неё, в узле «.лист-ещё__подпись».
        const подпись = узел.querySelector('.лист-ещё__подпись');
        if (подпись && строка) {
          подпись.textContent = строка.ключ === 'завершить' ? ТЕКСТ_ЗАВЕРШИТЬ : ТЕКСТ_В_МЕНЮ;
        }
        return;
      }
      const дверь = двери[описание.ключ];
      if (строка && описание.idСостояния && дверь && typeof дверь.состояние === 'function') {
        const состояние = document.getElementById(описание.idСостояния);
        if (состояние) состояние.textContent = дверь.состояние();
        // Для переключателей (звук, вибрация) обновляем aria-checked для читалок экрана:
        // 'true' когда состояние 'вкл', 'false' когда 'выкл'
        if (ПЕРЕКЛЮЧАТЕЛИ[описание.ключ]) {
          узел.setAttribute('aria-checked', дверь.состояние() === 'вкл' ? 'true' : 'false');
        }
      }
    });
  }

  /**
   * Подключить лист к разметке страницы.
   *
   * настройки:
   *   идЛиста          — id корневого узла листа, по умолчанию 'лист-игры';
   *   идФона            — id подложки, по умолчанию '<идЛиста>-фон';
   *   идОткрывающих     — список id кнопок «⋯», которые открывают лист
   *                        (по умолчанию ['кнопка-игра-ещё']);
   *   двери             — см. пояснение в шапке файла;
   *   экраныСЛистом     — список id экранов, где лист уместен (для
   *                        «освежитьКнопкуНастроек» — привязки пункта
   *                        «Настройки» в меню Telegram).
   *
   * Возвращает null, если узла листа на странице нет вовсе (страница
   * из старой памяти телефона, где листа ещё не было — не поломка).
   * Иначе — { открыть, закрыть, открыт, освежитьКнопкуНастроек }.
   */
  function подключить(настройки) {
    const н = настройки || {};
    const idЛиста = н.идЛиста || 'лист-игры';
    const лист = document.getElementById(idЛиста);
    if (!лист) return null;

    const двери = н.двери || {};
    const идОткрывающих = н.идОткрывающих || ['кнопка-игра-ещё'];
    const экраныСЛистом = н.экраныСЛистом || [];
    const idФона = н.идФона || (idЛиста + '-фон');

    let кнопкаОткрывшая = null;

    function открыт() {
      return !лист.classList.contains('скрыт');
    }

    /* На какую кнопку вернуть фокус при закрытии: первую видимую среди
       открывающих (на странице их может быть несколько — стол и лобби
       делят один и тот же лист). Ничего не видно — берём первую по счёту:
       так лист остаётся открываемым и без готового layout (в проверках). */
    function найтиОткрывающую() {
      for (let i = 0; i < идОткрывающих.length; i++) {
        const узел = document.getElementById(идОткрывающих[i]);
        if (узел && узел.offsetParent !== null) return узел;
      }
      return document.getElementById(идОткрывающих[0]) || null;
    }

    function открыть() {
      освежитьВидимость(двери);
      лист.classList.remove('скрыт');
      кнопкаОткрывшая = найтиОткрывающую();
      if (кнопкаОткрывшая) кнопкаОткрывшая.setAttribute('aria-expanded', 'true');
      const перваяСтрока = лист.querySelector('.лист-ещё__строка:not(.скрыт)');
      if (перваяСтрока) перваяСтрока.focus();
    }

    /** Закрыть лист. «вернутьФокус» — поставить его обратно на кнопку «⋯». */
    function закрыть(вернутьФокус) {
      if (!открыт()) return;
      лист.classList.add('скрыт');
      const кнопка = кнопкаОткрывшая || найтиОткрывающую();
      кнопкаОткрывшая = null;
      if (!кнопка) return;
      кнопка.setAttribute('aria-expanded', 'false');
      if (вернутьФокус) кнопка.focus();
    }

    /* --- Плашка «Завершить партию?» (штаб/план-выход-из-партии.md, Э1) ---
       Своей разметки у игры для неё пока нет (её рисует оформитель на Э2),
       поэтому лист строит общую плашку сам, один раз, и добавляет в конец
       document.body — id и классы см. у константы ID_ПЛАШКИ выше. */
    let дверьВПодтверждении = null;   // ради какой двери сейчас открыта плашка

    function подтверждениеОткрыто() {
      const узел = document.getElementById(ID_ПЛАШКИ);
      return Boolean(узел && !узел.classList.contains('скрыт'));
    }

    function узелПодтверждения() {
      const готовый = document.getElementById(ID_ПЛАШКИ);
      if (готовый) return готовый;

      const корень = document.createElement('div');
      корень.id = ID_ПЛАШКИ;
      корень.classList.add('плашка-завершить');
      корень.classList.add('скрыт');
      корень.setAttribute('role', 'alertdialog');
      корень.setAttribute('aria-modal', 'true');
      корень.setAttribute('aria-labelledby', ID_ПЛАШКИ + '-заголовок');

      const фонПлашки = document.createElement('div');
      фонПлашки.classList.add('плашка-завершить__фон');
      корень.appendChild(фонПлашки);

      const окно = document.createElement('div');
      окно.classList.add('плашка-завершить__окно');
      корень.appendChild(окно);

      const заголовокПлашки = document.createElement('h2');
      заголовокПлашки.id = ID_ПЛАШКИ + '-заголовок';
      заголовокПлашки.classList.add('плашка-завершить__заголовок');
      заголовокПлашки.textContent = 'Завершить партию?';
      окно.appendChild(заголовокПлашки);

      const текстПлашки = document.createElement('p');
      текстПлашки.classList.add('плашка-завершить__текст');
      окно.appendChild(текстПлашки);

      const кнопки = document.createElement('div');
      кнопки.classList.add('плашка-завершить__кнопки');
      окно.appendChild(кнопки);

      // «Вернуться к игре» — безопасный выбор, поэтому акцентная кнопка;
      // «Завершить» — опасное действие, отдельный класс для оформителя.
      const кнопкаНет = document.createElement('button');
      кнопкаНет.setAttribute('type', 'button');
      кнопкаНет.classList.add('кнопка');
      кнопкаНет.classList.add('кнопка--главная');
      кнопкаНет.classList.add('плашка-завершить__нет');
      кнопкаНет.textContent = 'Вернуться к игре';
      кнопки.appendChild(кнопкаНет);

      const кнопкаДа = document.createElement('button');
      кнопкаДа.setAttribute('type', 'button');
      кнопкаДа.classList.add('кнопка');
      кнопкаДа.classList.add('кнопка--опасная');
      кнопкаДа.classList.add('плашка-завершить__да');
      кнопкаДа.textContent = 'Завершить';
      кнопки.appendChild(кнопкаДа);

      document.body.appendChild(корень);

      фонПлашки.addEventListener('click', function () { закрытьПодтверждение(true); });
      кнопкаНет.addEventListener('click', function () { закрытьПодтверждение(true); });
      кнопкаДа.addEventListener('click', function () { закрытьПодтверждение(false); });

      return корень;
    }

    /** Открыть подтверждение ради двери «завершить»: текст последствия — её. */
    function открытьПодтверждение(дверьЗавершить) {
      дверьВПодтверждении = дверьЗавершить;
      const узел = узелПодтверждения();
      const текстУзел = узел.querySelector('.плашка-завершить__текст');
      if (текстУзел) {
        const текст = дверьЗавершить && дверьЗавершить.текст;
        текстУзел.textContent = typeof текст === 'function' ? текст() : (текст || '');
      }
      узел.classList.remove('скрыт');
      if (дверьЗавершить && typeof дверьЗавершить.пауза === 'function') дверьЗавершить.пауза();
    }

    /** Закрыть плашку. «вернутьсяКИгре» — нажали «Вернуться»/фон/Esc (партия
        продолжается, зовём дверь.продолжить); false — нажали «Завершить». */
    function закрытьПодтверждение(вернутьсяКИгре) {
      const узел = document.getElementById(ID_ПЛАШКИ);
      if (!узел || узел.classList.contains('скрыт')) return;
      узел.classList.add('скрыт');
      const дверь = дверьВПодтверждении;
      дверьВПодтверждении = null;
      if (вернутьсяКИгре) {
        if (дверь && typeof дверь.продолжить === 'function') дверь.продолжить();
      } else if (дверь && typeof дверь.действие === 'function') {
        дверь.действие();
      }
    }

    идОткрывающих.forEach(function (id) {
      const кнопка = document.getElementById(id);
      if (кнопка) кнопка.addEventListener('click', открыть);
    });

    const фон = document.getElementById(idФона);
    if (фон) фон.addEventListener('click', function () { закрыть(true); });   // нажали мимо листа

    const кнопкаЗакрыть = лист.querySelector('.лист-ещё__закрыть');
    if (кнопкаЗакрыть) кнопкаЗакрыть.addEventListener('click', function () { закрыть(true); });

    document.addEventListener('keydown', function (событие) {
      if (событие.key !== 'Escape') return;
      if (подтверждениеОткрыто()) { закрытьПодтверждение(true); return; }
      if (открыт()) закрыть(true);
    });

    /* Переходные строки закрывают лист и уводят на другой экран; звук и
       вибрация — переключатели (см. ПЕРЕКЛЮЧАТЕЛИ выше); строка на месте
       «В меню» решает по клику заново, какая дверь сейчас активна — партия
       могла начаться или закончиться, пока лист был закрыт. */
    ПОРЯДОК.forEach(function (описание) {
      const узел = document.getElementById(описание.id);
      if (!узел) return;
      if (описание.ключ === 'вМеню') {
        узел.addEventListener('click', function () {
          const активная = активнаяДверьМеню(двери);
          if (!активная) return;
          закрыть(false);
          if (активная.ключ === 'завершить') {
            открытьПодтверждение(активная.дверь);
          } else if (typeof активная.дверь.действие === 'function') {
            активная.дверь.действие();
          }
        });
        return;
      }
      const дверь = двери[описание.ключ];
      if (!дверь || typeof дверь.действие !== 'function') return;
      узел.addEventListener('click', function () {
        if (ПЕРЕКЛЮЧАТЕЛИ[описание.ключ]) {
          дверь.действие();
          освежитьВидимость(двери);   // сразу показать новое «вкл»/«выкл»
        } else {
          закрыть(false);
          дверь.действие();
        }
      });
    });

    /**
     * Пункт «Настройки» в меню ⋯ самого Telegram — открывает этот лист
     * там, где он уместен (внутри Telegram нашей верхней строки не видно,
     * шапку рисует он сам). Дверь в js/telegram.js сама снимает прежний
     * обработчик; вне Telegram и в его версиях старше 7.0 просто отвечает
     * «нет» и ничего не делает.
     */
    function освежитьКнопкуНастроек(idЭкрана) {
      if (typeof window === 'undefined' || !window.Телеграм ||
          typeof window.Телеграм.кнопкаНастроек !== 'function') return;
      const уместен = экраныСЛистом.indexOf(idЭкрана) !== -1;
      window.Телеграм.кнопкаНастроек(уместен ? открыть : null);
    }

    return { открыть: открыть, закрыть: закрыть, открыт: открыт, освежитьКнопкуНастроек: освежитьКнопкуНастроек };
  }

  const ЛистЕщё = { строкиЛиста: строкиЛиста, подключить: подключить, активнаяДверьМеню: активнаяДверьМеню };
  if (typeof module !== 'undefined' && module.exports) module.exports = ЛистЕщё;
  if (typeof window !== 'undefined') window.ЛистЕщё = ЛистЕщё;
})();
