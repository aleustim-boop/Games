/**
 * Лист «⋯» стола — общий для всех игр сборника.
 *
 * ЗАЧЕМ ОБЩИЙ ФАЙЛ. Один и тот же лист был написан дважды: в js/game.js
 * (дурак — «открытьЛистИгры», «закрытьЛистИгры», «изЛистаИгры»,
 * «освежитьКнопкуНастроек») и заново в js/нарды-экран.js. Копии уже
 * разошлись мелочами, а впереди ещё шашки и шахматы — было бы уже
 * четыре копии одного и того же (см. штаб/план-единый-стиль.md, Э1).
 * Теперь устройство живёт в одном месте, а игра лишь называет свои
 * «двери» — что должна сделать каждая строка листа.
 *
 * УСТРОЙСТВО, как у js/нижние-вкладки.js (сделан раньше, тот же приём):
 *   «строкиЛиста(двери)» — чистая функция без DOM: набор дверей ->
 *   список строк, которые сейчас должны быть видны, в фиксированном
 *   порядке. Она же используется для проверки в Node, без браузера
 *   (штаб/…). Остальное — обвязка: открытие, закрытие, привязка кнопок
 *   к уже готовой разметке в html каждой игры (сам html не строит —
 *   разметку листа рисует страница, здесь только показ/скрытие строк
 *   классом «скрыт» и поведение).
 *
 * ДВЕРИ, КОТОРЫЕ ЖДЁТ МОДУЛЬ. Игра передаёт объект «двери» — тех
 * строк, которых у неё нет вовсе, в объекте быть не должно (тогда
 * строки не будет, даже если кнопка для неё есть в разметке):
 *
 *   вМеню      { действие, видна }     — «видна()», если задана: идёт
 *                ли сейчас партия. Не задана — строка видна всегда
 *                (так у нард, которых Э1 ещё не учит прятать «В меню»).
 *   какИграть  { действие }
 *   звук       { действие, состояние } — «состояние()» -> 'вкл'/'выкл',
 *                показывается в строке, если в разметке есть узел
 *                «<id-кнопки>-состояние» заменён на «лист-игры-звук-
 *                состояние» (см. ПОРЯДОК ниже — так же, как у дурака).
 *   вибрация   { действие, доступна, состояние } — «доступна()»: нет
 *                функции или вернула false — строки нет вовсе (телефон
 *                вибрацию не умеет).
 *   оформление { действие }
 *   рекорды    { действие }
 *
 * Порядок строк ФИКСИРОВАН и совпадает с нынешним листом дурака:
 * В меню, Как играть, Звук, Вибрация, Оформление, Рекорды.
 *
 * ЧЕГО МОДУЛЬ НЕ ДЕЛАЕТ. Не строит разметку листа (id узлов те же, что
 * были всегда — на них держится style.css и старые проверки), не решает
 * сам, на каких экранах он уместен для «Настроек» Telegram — это говорит
 * игра через «экраныСЛистом» при подключении, потому что имена экранов
 * у каждой игры свои.
 */
(function () {
  'use strict';

  /* Порядок и id строк — те же, что в разметке дурака (index.html) и
     нард (нарды.html): переименовывать нельзя, за них держится style.css. */
  const ПОРЯДОК = [
    { ключ: 'вМеню', id: 'кнопка-лист-игры-меню' },
    { ключ: 'какИграть', id: 'кнопка-лист-игры-правила' },
    { ключ: 'звук', id: 'кнопка-лист-игры-звук', idСостояния: 'лист-игры-звук-состояние' },
    { ключ: 'вибрация', id: 'кнопка-лист-игры-вибрация', idСостояния: 'лист-игры-вибрация-состояние' },
    { ключ: 'оформление', id: 'кнопка-лист-игры-оформление' },
    { ключ: 'рекорды', id: 'кнопка-лист-игры-рекорды' }
  ];

  /* Строки-переключатели: клик их не закрывает — человеку должно быть
     видно, как слово «вкл» сменилось на «выкл», как у листа «Ещё» витрины. */
  const ПЕРЕКЛЮЧАТЕЛИ = { звук: true, вибрация: true };

  /**
   * Список строк, которые сейчас видны — чистые данные, без DOM.
   * Работает и в браузере, и в Node (для проверки без браузера).
   * Дверь не передана — строки нет вовсе; «вМеню» и «вибрация» решают
   * видимость ещё и по своим полям (см. пояснение в шапке файла).
   */
  function строкиЛиста(двери) {
    двери = двери || {};
    const строки = [];
    ПОРЯДОК.forEach(function (описание) {
      const дверь = двери[описание.ключ];
      if (!дверь) return;
      if (описание.ключ === 'вМеню' && typeof дверь.видна === 'function' && !дверь.видна()) return;
      if (описание.ключ === 'вибрация') {
        const доступна = typeof дверь.доступна === 'function' && дверь.доступна();
        if (!доступна) return;
      }
      строки.push({ ключ: описание.ключ, id: описание.id });
    });
    return строки;
  }

  /** Показать/спрятать строки в уже готовой разметке и обновить текст «вкл/выкл». */
  function освежитьВидимость(двери) {
    const видимые = Object.create(null);
    строкиЛиста(двери).forEach(function (с) { видимые[с.ключ] = true; });
    ПОРЯДОК.forEach(function (описание) {
      const узел = document.getElementById(описание.id);
      if (!узел) return;   // в разметке этой игры такой строки нет вовсе — тихо
      const показать = Boolean(видимые[описание.ключ]);
      узел.classList.toggle('скрыт', !показать);
      const дверь = двери[описание.ключ];
      if (показать && описание.idСостояния && дверь && typeof дверь.состояние === 'function') {
        const состояние = document.getElementById(описание.idСостояния);
        if (состояние) состояние.textContent = дверь.состояние();
      }
    });
  }

  /**
   * Подключить лист к разметке страницы.
   *
   * настройки:
   *   идЛиста          — id корневого узла листа, по умолчанию 'лист-игры';
   *   идФона            — id подложки, по умолчанию '<идЛиста>-фон';
   *   идОткрывающих     — список id кнопок «⋯», которые открывают лист
   *                        (по умолчанию ['кнопка-игра-ещё']);
   *   двери             — см. пояснение в шапке файла;
   *   экраныСЛистом     — список id экранов, где лист уместен (для
   *                        «освежитьКнопкуНастроек» — привязки пункта
   *                        «Настройки» в меню Telegram).
   *
   * Возвращает null, если узла листа на странице нет вовсе (страница
   * из старой памяти телефона, где листа ещё не было — не поломка).
   * Иначе — { открыть, закрыть, открыт, освежитьКнопкуНастроек }.
   */
  function подключить(настройки) {
    const н = настройки || {};
    const idЛиста = н.идЛиста || 'лист-игры';
    const лист = document.getElementById(idЛиста);
    if (!лист) return null;

    const двери = н.двери || {};
    const идОткрывающих = н.идОткрывающих || ['кнопка-игра-ещё'];
    const экраныСЛистом = н.экраныСЛистом || [];
    const idФона = н.идФона || (idЛиста + '-фон');

    let кнопкаОткрывшая = null;

    function открыт() {
      return !лист.classList.contains('скрыт');
    }

    /* На какую кнопку вернуть фокус при закрытии: первую видимую среди
       открывающих (на странице их может быть несколько — стол и лобби
       делят один и тот же лист). Ничего не видно — берём первую по счёту:
       так лист остаётся открываемым и без готового layout (в проверках). */
    function найтиОткрывающую() {
      for (let i = 0; i < идОткрывающих.length; i++) {
        const узел = document.getElementById(идОткрывающих[i]);
        if (узел && узел.offsetParent !== null) return узел;
      }
      return document.getElementById(идОткрывающих[0]) || null;
    }

    function открыть() {
      освежитьВидимость(двери);
      лист.classList.remove('скрыт');
      кнопкаОткрывшая = найтиОткрывающую();
      if (кнопкаОткрывшая) кнопкаОткрывшая.setAttribute('aria-expanded', 'true');
      const перваяСтрока = лист.querySelector('.лист-ещё__строка:not(.скрыт)');
      if (перваяСтрока) перваяСтрока.focus();
    }

    /** Закрыть лист. «вернутьФокус» — поставить его обратно на кнопку «⋯». */
    function закрыть(вернутьФокус) {
      if (!открыт()) return;
      лист.classList.add('скрыт');
      const кнопка = кнопкаОткрывшая || найтиОткрывающую();
      кнопкаОткрывшая = null;
      if (!кнопка) return;
      кнопка.setAttribute('aria-expanded', 'false');
      if (вернутьФокус) кнопка.focus();
    }

    идОткрывающих.forEach(function (id) {
      const кнопка = document.getElementById(id);
      if (кнопка) кнопка.addEventListener('click', открыть);
    });

    const фон = document.getElementById(idФона);
    if (фон) фон.addEventListener('click', function () { закрыть(true); });   // нажали мимо листа

    const кнопкаЗакрыть = лист.querySelector('.лист-ещё__закрыть');
    if (кнопкаЗакрыть) кнопкаЗакрыть.addEventListener('click', function () { закрыть(true); });

    document.addEventListener('keydown', function (событие) {
      if (событие.key === 'Escape' && открыт()) закрыть(true);
    });

    /* Переходные строки закрывают лист и уводят на другой экран; звук и
       вибрация — переключатели (см. ПЕРЕКЛЮЧАТЕЛИ выше). */
    ПОРЯДОК.forEach(function (описание) {
      const дверь = двери[описание.ключ];
      const узел = document.getElementById(описание.id);
      if (!узел || !дверь || typeof дверь.действие !== 'function') return;
      узел.addEventListener('click', function () {
        if (ПЕРЕКЛЮЧАТЕЛИ[описание.ключ]) {
          дверь.действие();
          освежитьВидимость(двери);   // сразу показать новое «вкл»/«выкл»
        } else {
          закрыть(false);
          дверь.действие();
        }
      });
    });

    /**
     * Пункт «Настройки» в меню ⋯ самого Telegram — открывает этот лист
     * там, где он уместен (внутри Telegram нашей верхней строки не видно,
     * шапку рисует он сам). Дверь в js/telegram.js сама снимает прежний
     * обработчик; вне Telegram и в его версиях старше 7.0 просто отвечает
     * «нет» и ничего не делает.
     */
    function освежитьКнопкуНастроек(idЭкрана) {
      if (typeof window === 'undefined' || !window.Телеграм ||
          typeof window.Телеграм.кнопкаНастроек !== 'function') return;
      const уместен = экраныСЛистом.indexOf(idЭкрана) !== -1;
      window.Телеграм.кнопкаНастроек(уместен ? открыть : null);
    }

    return { открыть: открыть, закрыть: закрыть, открыт: открыт, освежитьКнопкуНастроек: освежитьКнопкуНастроек };
  }

  const ЛистЕщё = { строкиЛиста: строкиЛиста, подключить: подключить };
  if (typeof module !== 'undefined' && module.exports) module.exports = ЛистЕщё;
  if (typeof window !== 'undefined') window.ЛистЕщё = ЛистЕщё;
})();
