  /** Выполнить одно действие места — либо дверь (пока только «позвать»), либо запрос серверу. */
  function выполнитьДействиеМеста(действие, номерМеста) {
    закрытьЛистМеста(false);
    if (действие.дверь) {
      // Единственная дверь у места сейчас — приглашение на свободное место.
      вызватьПозвать();
      return;
    }
    запуститьДействие(действие.намерения, номерМеста);
  }

  function открытьЛистМеста(узелМеста, место) {
    const лист = узел('лист-места');
    if (!лист) { выполнитьДействиеМеста(место.действия[0], место.номер); return; }
    текстомУзла('лист-места-заголовок', место.подпись || 'Место за столом');
    const список = узел('лист-места-действия');
    if (список) {
      список.innerHTML = '';
      место.действия.forEach(function (действие) {
        const строка = document.createElement('button');
        строка.type = 'button';
        строка.className = 'лист-ещё__строка';
        const подпись = document.createElement('span');
        подпись.className = 'лист-ещё__подпись';
        подпись.textContent = действие.подпись;
        строка.appendChild(подпись);
        строка.addEventListener('click', function () { выполнитьДействиеМеста(действие, место.номер); });
        список.appendChild(строка);
      });
    }
    лист.classList.remove('скрыт');
    местоОткрывшееЛист = узелМеста ? узелМеста.корень : null;
    const перваяСтрока = список && список.querySelector('.лист-ещё__строка');
    if (перваяСтрока) перваяСтрока.focus();
  }

