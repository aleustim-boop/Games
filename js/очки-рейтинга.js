/* =====================================================================
   ОЧКИ РЕЙТИНГА ЗА ПАРТИЮ С БОТОМ — ОБЩАЯ ДВЕРЬ ДЛЯ ЛЮБОЙ ИГРЫ.

   Владелец решил: партии с ботом дают очки рейтинга во всех играх, не
   только в дураке. У дурака это уже работает через js/game.js и
   js/сеть.js (билет берётся на старте партии, сдаётся на итоге — см.
   там же и server/билеты.js, где честно написано, что билет даёт
   и чего не даёт). Здесь — та же самая дверь на маршруты /билет
   и /итог-с-ботом, но отдельным маленьким файлом, чтобы подключать её
   без всего остального, что тянет за собой js/game.js. Саму сеть этот
   файл не поднимает: страница обязана подключить и js/сеть.js — без неё
   очков не будет (подробности ниже).

   Как этим пользоваться из экрана игры (партия с ботом):
     const ручка = ОчкиРейтинга.взятьБилет('шашки', уровень);   // старт партии с ботом
     ...
     ОчкиРейтинга.сдать(ручка, 'победа'|'ничья'|'поражение')    // конец партии
       .then(function (ответ) {
         написать('итог-рейтинга', ОчкиРейтинга.словаИтога(ответ));
       });

   Та же дверь для игр-головоломок с рейтингом по лучшему счёту (2048,
   судоку…, план штаб/план-рейтинг-бот-и-счёт.md, этап Э4): свои
   маршруты /билет-счёта и /счёт, своя память на сервере (см.
   server/лучший-счёт.js — оттуда же взяты имена полей ответа):
     const ручка = ОчкиРейтинга.взятьБилетСчёта('2048', 'classic');   // старт партии
     ...
     ОчкиРейтинга.сдатьСчёт(ручка, { счёт: 4096 })                    // или { секунд: 812 }
       .then(function (ответ) {
         if (ответ.улучшение) показатьРекорд(ответ.значение);
       });

   Адрес сервера этот файл НЕ ищет сам: по договору проекта единственное
   место браузера, которое знает адрес сервера, — js/сеть.js (см. CLAUDE.md,
   раздел «Договоры»). Адрес спрашиваем через её дверь window.Сеть.адрес().
   Нет js/сеть.js на странице — тихий отказ и ни одного запроса, даже
   если Telegram есть: это единственный источник правды об адресе,
   заводить второй здесь нельзя.

   Обещания никогда не срываются (не бросают и не отклоняются): нет
   Telegram, нет window.Сеть, сервер молчит или отказал — тихий
   отказ, партия от этого не ломается, просто очков не будет.

   Ручка — своя на каждую партию: экран заводит новую вызовом «взятьБилет»
   при каждом старте. Так поздний ответ одной партии никогда не попадёт
   в другую, даже если игрок успел начать новую партию раньше, чем
   ответил сервер.
   ===================================================================== */

'use strict';

(function () {

  /* Тот же особый заголовок, что и в js/сеть.js: без него быстрый туннель
     (cloudflare) может ответить страницей-предупреждением вместо JSON. */
  const ПРОПУСК_ЧЕРЕЗ_ТУННЕЛЬ = { 'bypass-tunnel-reminder': 'true' };
  const ОБЫЧНОЕ_ОЖИДАНИЕ = 10 * 1000;

  /* Фразы отказа при СДАЧЕ билета — слово в слово те же, что показывает
     js/game.js на плашке итога дурака (там же — ПРИЧИНЫ_ЛИМИТА_БИЛЕТА).
     Дурак остаётся на своей копии, эта — для всех остальных игр. Список
     меняет только штаб, вместе с сервером. */
  const ПРИЧИНЫ_ЛИМИТА = [
    'Партия с ботом засчитывается не чаще раза в сорок секунд',
    'На сегодня партий с ботом засчитано достаточно — снова завтра',
    'На сегодня очки за ботов кончились — партии с ботом снова засчитаются завтра'
  ];

  /** Подпись Telegram — без неё сервер не узнает, кто играл (как в js/сеть.js). */
  function подписьTelegram() {
    try {
      const приложение = window.Telegram && window.Telegram.WebApp;
      return (приложение && приложение.initData) || '';
    } catch (сбой) {
      return '';
    }
  }

  /**
   * Адрес сервера — только через дверь js/сеть.js (window.Сеть.адрес()):
   * там уже решён и спор вписанного адреса с адресом из ссылки, и запасной
   * адрес по месту открытия страницы. Заводить второй источник правды
   * об адресе в обход неё нельзя (см. CLAUDE.md, «Договоры»). Нет
   * window.Сеть на странице или у неё нет этой двери — честное «не знаю»,
   * а не собственная догадка: запрос дальше вообще не уйдёт.
   */
  function адресСервера() {
    try {
      if (window.Сеть && typeof window.Сеть.адрес === 'function') {
        return window.Сеть.адрес() || '';
      }
    } catch (сбой) { /* Сеть на странице сломана — адреса не знаем */ }
    return '';
  }

  /**
   * Один запрос к серверу. Никогда не падает и не отклоняет обещание:
   * любая беда (нет адреса, нет fetch, сеть оборвалась, ответ не JSON)
   * оборачивается в null — дальше это читается как честный отказ.
   */
  function запрос(путь, тело) {
    let адрес = '';
    try {
      адрес = адресСервера();
    } catch (сбой) {
      адрес = '';
    }
    if (!адрес || typeof fetch !== 'function') return Promise.resolve(null);

    let управление = null;
    let сторож = null;
    try {
      управление = typeof AbortController !== 'undefined' ? new AbortController() : null;
      сторож = setTimeout(function () { if (управление) управление.abort(); }, ОБЫЧНОЕ_ОЖИДАНИЕ);
    } catch (сбой) { /* без сторожа запрос всё равно уйдёт */ }

    const настройки = {
      method: 'POST',
      headers: Object.assign({ 'Content-Type': 'application/json' }, ПРОПУСК_ЧЕРЕЗ_ТУННЕЛЬ),
      body: JSON.stringify(тело || {})
    };
    if (управление) настройки.signal = управление.signal;

    let ответ;
    try {
      ответ = fetch(адрес + путь, настройки);
    } catch (сбой) {
      if (сторож) clearTimeout(сторож);
      return Promise.resolve(null);
    }
    return ответ
      .then(function (ответ) {
        return ответ.json().then(
          function (данные) { return данные && typeof данные === 'object' ? данные : null; },
          function () { return null; }
        );
      })
      .catch(function () { return null; })
      .then(function (итог) {
        if (сторож) clearTimeout(сторож);
        return итог;
      });
  }

  /** Пустой отказ на сдачу — одна форма на все беды. */
  function отказИтога(причина) {
    return { ок: false, очков: 0, причина: причина || '' };
  }

  /**
   * Взять билет на партию с ботом: { игра, уровень } → ручка.
   * Ручка возвращается СРАЗУ — партия не ждёт ответа сервера и стартует
   * как обычно. Билет ляжет в ручку сам, когда придёт (или не ляжет —
   * нет Telegram, сервер отказал, игра или уровень ему незнакомы).
   */
  function взятьБилет(игра, уровень) {
    const ручка = { билет: '', партияНеКорочеСекунд: 0, сдана: false, готово: null };
    const подпись = подписьTelegram();
    if (!подпись) {
      ручка.готово = Promise.resolve();   // без Telegram — тихо ничего, даже не стучимся
      return ручка;
    }
    ручка.готово = запрос('/билет', { initData: подпись, игра: игра, уровень: уровень })
      .then(function (данные) {
        if (данные && данные.ок === true && typeof данные.билет === 'string' && данные.билет) {
          ручка.билет = данные.билет;
          ручка.партияНеКорочеСекунд = Number.isInteger(данные.партияНеКорочеСекунд) ? данные.партияНеКорочеСекунд : 0;
        }
      });
    return ручка;
  }

  /**
   * Сдать билет и исход партии: (ручка, 'победа'|'ничья'|'поражение') →
   * Promise { ок, очков, причина }. Обещание никогда не срывается.
   * Билета в ручке нет (ещё не пришёл, не выдан, нет Telegram) — сдачи
   * не будет. Эта ручка уже сдавалась — повторная сдача в сеть не уходит,
   * билет одноразовый.
   */
  function сдать(ручка, исход) {
    if (!ручка || ручка.сдана) return Promise.resolve(отказИтога(''));
    /* Помечаем сразу, а не после ответа сервера: если «сдать» позвали
       дважды подряд, не дожидаясь первого ответа, второй вызов должен
       увидеть отметку уже сейчас — иначе оба уйдут в сеть одновременно. */
    ручка.сдана = true;
    const дождатьсяБилета = ручка.готово || Promise.resolve();
    return дождатьсяБилета
      .then(function () {
        if (!ручка.билет) return отказИтога('');
        const подпись = подписьTelegram();
        if (!подпись) return отказИтога('Очки за партии с ботом начисляются только в Telegram');
        return запрос('/итог-с-ботом', { initData: подпись, билет: ручка.билет, исход: исход })
          .then(function (данные) {
            if (!данные) return отказИтога('Сервер игры не ответил');
            return {
              ок: данные.ок === true,
              очков: Number.isInteger(данные.очков) ? данные.очков : 0,
              причина: typeof данные.причина === 'string' ? данные.причина : ''
            };
          });
      })
      .catch(function () { return отказИтога(''); });
  }

  /** Строка для плашки итога по ответу «сдать» — те же три фразы, что у дурака. */
  function словаИтога(ответ) {
    if (ответ && ответ.ок === true) {
      const очков = Number.isInteger(ответ.очков) ? ответ.очков : 0;
      // 0 очков (лёгкий бот) — партия и так засчиталась, но хвастаться нечем.
      return очков > 0 ? ('+' + очков + ' к рейтингу') : '';
    }
    if (ответ && ПРИЧИНЫ_ЛИМИТА.indexOf(ответ.причина) !== -1) return ответ.причина;
    return '';
  }

  /** Пустой отказ на сдачу СЧЁТА — своя форма, у неё нет «очков», зато есть «улучшение» и «значение». */
  function отказСчёта(причина) {
    return { ок: false, улучшение: false, значение: null, причина: причина || '' };
  }

  /**
   * Взять билет на партию-головоломку (2048, судоку…): { игра, режим } →
   * ручка. Тот же приём, что и «взятьБилет» выше: ручка возвращается
   * СРАЗУ, партия не ждёт ответа сервера. Билет и «зерно» (задел под
   * будущий повтор партии на сервере, план Э4.9) лягут в ручку сами,
   * когда придёт ответ — или не лягут, как и у обычного билета.
   */
  function взятьБилетСчёта(игра, режим) {
    const ручка = { билет: '', зерно: 0, сдана: false, готово: null };
    const подпись = подписьTelegram();
    if (!подпись) {
      ручка.готово = Promise.resolve();   // без Telegram — тихо ничего, даже не стучимся
      return ручка;
    }
    ручка.готово = запрос('/билет-счёта', { initData: подпись, игра: игра, режим: режим })
      .then(function (данные) {
        if (данные && данные.ок === true && typeof данные.билет === 'string' && данные.билет) {
          ручка.билет = данные.билет;
          ручка.зерно = Number.isInteger(данные.зерно) ? данные.зерно : 0;
        }
      });
    return ручка;
  }

  /**
   * Сдать результат партии-головоломки: (ручка, { счёт } | { секунд }) →
   * Promise { ок, улучшение, значение, причина }. Обещание никогда не
   * срывается. Значение — ровно то, что прислала игра (одно число под
   * своим именем, «счёт» или «секунд»: какая мера у игры, решает
   * js/игры-реестр.js на сервере, здесь это не проверяется и не
   * подменяется). Билета в ручке нет или он уже сдан — сдачи не будет.
   */
  function сдатьСчёт(ручка, значение) {
    if (!ручка || ручка.сдана) return Promise.resolve(отказСчёта(''));
    // Помечаем сразу — той же причиной, что и у «сдать» выше: повторный
    // вызов до ответа сервера не должен уйти в сеть вторым запросом.
    ручка.сдана = true;
    const дождатьсяБилета = ручка.готово || Promise.resolve();
    return дождатьсяБилета
      .then(function () {
        if (!ручка.билет) return отказСчёта('');
        const подпись = подписьTelegram();
        if (!подпись) return отказСчёта('Рейтинг по счёту ведётся только в Telegram');
        const тело = Object.assign({ initData: подпись, билет: ручка.билет }, значение || {});
        return запрос('/счёт', тело)
          .then(function (данные) {
            if (!данные) return отказСчёта('Сервер игры не ответил');
            return {
              ок: данные.ок === true,
              улучшение: данные.улучшение === true,
              значение: Number.isFinite(данные.значение) ? данные.значение : null,
              причина: typeof данные.причина === 'string' ? данные.причина : ''
            };
          });
      })
      .catch(function () { return отказСчёта(''); });
  }

  window.ОчкиРейтинга = {
    взятьБилет: взятьБилет,
    сдать: сдать,
    словаИтога: словаИтога,
    взятьБилетСчёта: взятьБилетСчёта,
    сдатьСчёт: сдатьСчёт
  };

})();
