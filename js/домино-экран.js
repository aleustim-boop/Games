/* Отсчёт минуты на ход (домино от трёх мест) — чистые функции без страницы:
   по виду и часам говорят, что показать. Вынесены отдельно, чтобы проверка
   на node (tests/домино-отсчёт-на-экране.js) брала их из этого же файла,
   а не из своей копии — приём как у js/домино-бот.js. */
(function () {
  const ПОРОГ_МАЛО = 10;   // на последних десяти секундах отсчёт краснеет

  /** Сколько секунд осталось сейчас: присланное число минус прошедшее с ответа время,
      округлённое ВВЕРХ (как считает сервер): «0 с» горит только когда ход уже просрочен,
      а на новом ответе число не прыгает вверх. Не ниже нуля и не выше присланного. */
  function секундыСейчас(остаток, получено, сейчас) {
    const прошло = Math.max(0, (сейчас - получено) / 1000);
    return Math.max(0, Math.min(остаток, Math.ceil(остаток - прошло)));
  }

  const числоЧасов = остаток => typeof остаток === 'number' && Number.isFinite(остаток);
  // Виды событий комнаты, слова которых экран показывает в подсказке (признак ставит сервер).
  const СЛОВА_ПРО_ВРЕМЯ = ['ход-по-времени', 'раунд-сам'];

  /* Что показать. вход: { остаток — секунды из вида сервера (null/нет — часов нет),
     получено, сейчас — метки времени в мс, фаза, ход, я — номера мест }.
     Часов нет (стол вдвоём, игра с ботом) или раунд не идёт — null: на итоге
     раунда отсчёта не рисуем, ход там — кнопка в окне результата. */
  function отсчёт(вход) {
    if (!вход || !числоЧасов(вход.остаток)) return null;
    if (вход.фаза !== 'игра') return null;
    const секунд = секундыСейчас(вход.остаток, вход.получено, вход.сейчас);
    // Между числом и «с» неразрывный пробел: «с» не уезжает на отдельную строку.
    return { секунд, мало: секунд <= ПОРОГ_МАЛО, укого: вход.ход === вход.я ? 'я' : 'сосед', текст: секунд + ' с' };
  }

  /* На итоге раунда часы тоже идут: не нажал хозяин — раунд начнётся сам, иначе
     стол завис бы. Говорим об этом всем за столом. Вдвоём часов нет — null. */
  function отсчётРаунда(вход) {
    if (!вход || !числоЧасов(вход.остаток) || вход.фаза !== 'итог') return null;
    const секунд = секундыСейчас(вход.остаток, вход.получено, вход.сейчас);
    return { секунд, текст: 'Следующий раунд начнётся через ' + секунд + ' с' };   // неразрывный пробел, как в пилюле
  }

  /* Слова события комнаты в подсказку берём ТОЛЬКО про время: комната дописывает
     к событиям общие слова голосования и слова дурака про «карты». Отличаем по
     виду события, который собирает сервер (видСобытия), а не по тексту. */
  function словаПроВремя(видСобытия, событие) {
    return СЛОВА_ПРО_ВРЕМЯ.includes(видСобытия) && typeof событие === 'string' ? событие : '';
  }

  /* Строка подсказки под столом. Ходящему события не мешают — у него своя
     подсказка «Выберите кость». Остальным: отсчёт раунда, потом слова про время,
     потом слова о соседях (вышел — играет бот, вернулся), потом обычная запасная строка. */
  function подсказка(вход) {
    if (вход.моёХод) return вход.своя;
    return вход.строкаРаунда || словаПроВремя(вход.видСобытия, вход.событие) || вход.словаСтола || вход.запасная;
  }

  /* Всё, что экран рисует по часам, одним ответом: пилюля в плашке, строка
     итога раунда, слова про время. Без сети (партия с ботами) — ничего. */
  function чтоНарисовать(вход) {
    if (!вход || !вход.поСети) return { пилюля: null, строкаРаунда: null, слова: '' };
    return { пилюля: отсчёт(вход), строкаРаунда: отсчётРаунда(вход), слова: словаПроВремя(вход.видСобытия, вход.событие) };
  }

  const api = { отсчёт, отсчётРаунда, словаПроВремя, подсказка, чтоНарисовать, секундыСейчас, ПОРОГ_МАЛО };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  if (typeof window !== 'undefined') window.ДоминоОтсчёт = api;
})();
