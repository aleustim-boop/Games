/* =====================================================================
   Экран «Играть онлайн»: сервер сам подбирает соперника (дурак).

   Одна дверь наружу:
       window.ЭкранПодбора.открыть()
   Кнопку, которая её зовёт, этот файл сам не вешает — id для неё в
   лобби сегодня нет (карточка «Играть онлайн» из ТЕКСТЫ_ЛОББИ.онлайн,
   js/дурак-путь.js, никуда не подключена: id «лобби-онлайн» занят
   другой, ручной функцией «Найти игру», js/открытые-столы.js). Дверь
   открывает js/дурак-путь.js, когда штаб решит, откуда её звать —
   см. отчёт исполнителя.

   Откуда берутся данные и как устроено сведение пары — целиком
   в js/сеть.js (Сеть.встатьВОчередь, Сеть.подождатьСоперника,
   Сеть.отменитьПодбор): этот файл только просит соперника и рисует
   ожидание, второй сетевой дороги не прокладывает. Вход в комнату,
   когда пара сведена, делает сама Сеть.js (через начатьЖизньВКомнате —
   ту же дверь, что вход по коду), а не этот файл.

   Бота сервер сам не сажает (решение владельца 30.09: «бота не сажать,
   только по кнопке»): экран честно пишет «Ищем живого соперника…» и
   даёт кнопку «Играть с ботом» — игрок садится с ботом только по ней.
   Когда сервер сказал «свели» (человек или бот по кнопке) — экран просто
   переходит в игру.

   Разметку строим сами, как это делает js/открытые-столы.js: своих
   узлов на index.html для этого экрана нет, и мы вставляем его в общий
   контейнер #приложение теми же классами, что уже есть в style.css
   (.экран, .заголовок, .сеть-ожидание, .сеть-сообщение, .кнопка) —
   ни одного нового стиля из кода.
   ===================================================================== */

'use strict';

(function () {

  const ЭКРАН = 'экран-подбор-соперника';
  const УЗЕЛ_ОЖИДАНИЕ = 'подбор-ожидание';
  const УЗЕЛ_СООБЩЕНИЕ = 'подбор-сообщение';
  const КНОПКА_БОТ = 'подбор-с-ботом';
  const КНОПКА_ОТМЕНА = 'подбор-отмена';
  const КНОПКА_НАЗАД = 'подбор-назад';

  const СЧЁТЧИК_КАЖДЫЕ = 1000;

  /* Растёт при каждом открытии, отмене и «Назад». По нему опоздавший
     ответ сервера узнаётся и выбрасывается — без этого счётчик или
     сообщение об ошибке могли бы нарисоваться поверх уже закрытого
     экрана или поверх свежего открытия того же. */
  let поколение = 0;
  let началоОжидания = 0;
  let таймерСчётчика = null;
  let откудаПришли = 'экран-лобби';

  function узел(id) { return document.getElementById(id); }

  /* -------------------------------------------------------------------
     Экран
     ------------------------------------------------------------------- */

  /** Показать экран. Мост из js/game.js умеет заодно погасить ленту и
      панель знаков — своей переключалкой это не повторить, поэтому зовём
      его первым. Моста нет — переключаем классы сами (тот же приём, что
      в js/открытые-столы.js). */
  function показатьЭкран(id) {
    if (window.ИграПоСети && typeof window.ИграПоСети.экран === 'function') {
      window.ИграПоСети.экран(id);
      return;
    }
    for (const экран of document.querySelectorAll('.экран')) {
      экран.classList.toggle('экран--виден', экран.id === id);
    }
  }

  function текущийЭкран() {
    const открытый = document.querySelector('.экран.экран--виден');
    return (открытый && открытый.id) || 'экран-лобби';
  }

  function попытатьсяПривязатьСтрелку(действие) {
    try {
      if (window.Телеграм && typeof window.Телеграм.показатьСтрелку === 'function') {
        window.Телеграм.показатьСтрелку(действие);
      }
    } catch (сбой) {
      /* нет Telegram — ничего страшного */
    }
  }

  /* -------------------------------------------------------------------
     Своя разметка (index.html её не пишет)
     ------------------------------------------------------------------- */

  function хозяинЭкранов() {
    const хозяин = document.getElementById('приложение') || document.body;
    return (хозяин && typeof хозяин.appendChild === 'function') ? хозяин : null;
  }

  function кнопкаЭл(id, текст, класс, действие) {
    const н = document.createElement('button');
    н.type = 'button';
    н.id = id;
    н.className = класс;
    н.textContent = текст;
    if (действие) н.addEventListener('click', действие);
    return н;
  }

  function построитьЭкран() {
    const хозяин = хозяинЭкранов();
    if (!хозяин) return null;

    const секция = document.createElement('section');
    секция.id = ЭКРАН;
    секция.className = 'экран';

    const заголовок = document.createElement('h2');
    заголовок.className = 'заголовок';
    заголовок.textContent = 'Играть онлайн';
    секция.appendChild(заголовок);

    const ожидание = document.createElement('p');
    ожидание.id = УЗЕЛ_ОЖИДАНИЕ;
    ожидание.className = 'сеть-ожидание';
    секция.appendChild(ожидание);

    const сообщение = document.createElement('p');
    сообщение.id = УЗЕЛ_СООБЩЕНИЕ;
    сообщение.className = 'сеть-сообщение скрыт';
    секция.appendChild(сообщение);

    секция.appendChild(кнопкаЭл(КНОПКА_БОТ, 'Играть с ботом', 'кнопка', нажалиСБотом));
    секция.appendChild(кнопкаЭл(КНОПКА_ОТМЕНА, 'Отменить', 'кнопка', нажалиОтменить));
    секция.appendChild(кнопкаЭл(КНОПКА_НАЗАД, 'Назад', 'кнопка скрыт', назад));

    хозяин.appendChild(секция);
    return секция;
  }

  function убедитьсяЧтоЭкранЕсть() {
    return узел(ЭКРАН) || построитьЭкран();
  }

  /* -------------------------------------------------------------------
     Счётчик времени ожидания и сообщения
     ------------------------------------------------------------------- */

  /** Сколько уже ищем — по-человечески, без «0 минут». */
  function словамиИдётПоиск(секунд) {
    const с = Math.max(0, Math.floor(секунд));
    if (с < 60) return 'Ищем соперника… ' + с + ' с';
    const минут = Math.floor(с / 60);
    const остаток = с % 60;
    return 'Ищем соперника… ' + минут + ' мин ' + остаток + ' с';
  }

  function написатьОжидание(текст) {
    const место = узел(УЗЕЛ_ОЖИДАНИЕ);
    if (место) место.textContent = текст;
  }

  function запуститьСчётчик() {
    остановитьСчётчик();
    началоОжидания = Date.now();
    написатьОжидание(словамиИдётПоиск(0));
    таймерСчётчика = setInterval(function () {
      написатьОжидание(словамиИдётПоиск((Date.now() - началоОжидания) / 1000));
    }, СЧЁТЧИК_КАЖДЫЕ);
  }

  function остановитьСчётчик() {
    if (таймерСчётчика !== null) {
      clearInterval(таймерСчётчика);
      таймерСчётчика = null;
    }
  }

  function показатьСообщение(текст) {
    const место = узел(УЗЕЛ_СООБЩЕНИЕ);
    if (!место) return;
    место.textContent = текст || '';
    место.classList.toggle('скрыт', !текст);
  }

  function показатьКнопкуОтмена(видно) {
    const кнопка = узел(КНОПКА_ОТМЕНА);
    if (кнопка) кнопка.classList.toggle('скрыт', !видно);
  }

  /** Кнопка «Играть с ботом»: видна, пока ждём; на время запроса гасится
      (disabled), чтобы двойное нажатие не слало второй запрос. */
  function показатьКнопкуБота(видно, доступна) {
    const кнопка = узел(КНОПКА_БОТ);
    if (!кнопка) return;
    кнопка.classList.toggle('скрыт', !видно);
    кнопка.disabled = !доступна;
  }

  function показатьКнопкуНазад(видно) {
    const кнопка = узел(КНОПКА_НАЗАД);
    if (кнопка) кнопка.classList.toggle('скрыт', !видно);
  }

  /* -------------------------------------------------------------------
     Настройка игрока: «переводной» — из той же памяти, что и у игры
     с ботами (решение штаба, план-онлайн-подбор.md, п.2: подбор берёт
     правила из памяти, без своего выбора). Ключ — общий, из
     window.ДуракПуть.КЛЮЧИ_ПАМЯТИ (js/дурак-путь.js), строкой на
     запасной случай, если тот файл почему-то не загрузился.
     ------------------------------------------------------------------- */

  function переводнойИзПамяти() {
    try {
      const ключ = (window.ДуракПуть && window.ДуракПуть.КЛЮЧИ_ПАМЯТИ &&
                    window.ДуракПуть.КЛЮЧИ_ПАМЯТИ.переводной) || 'transfer_durak';
      return window.localStorage.getItem(ключ) === 'да';
    } catch (сбой) {
      return false;   // памяти нет или запрещена — как у новичка без выбора
    }
  }

  /* -------------------------------------------------------------------
     Ход подбора: встать в очередь, затем крутить длинный опрос
     ------------------------------------------------------------------- */

  function свериться(моёПоколение) { return моёПоколение === поколение; }

  function итогНеВышел(моёПоколение, причина) {
    if (!свериться(моёПоколение)) return;
    остановитьСчётчик();
    показатьСообщение(причина || 'Играть онлайн сейчас не вышло.');
    показатьКнопкуБота(false, false);
    показатьКнопкуОтмена(false);
    показатьКнопкуНазад(true);
  }

  /**
   * Пара сведена — человек или бот по кнопке. К этому моменту Сеть.js уже провела
   * игрока через начатьЖизньВКомнате: партия поднята и правильный
   * экран (экран-игры) уже показан, синхронно, раньше, чем сюда
   * дошёл этот вызов. Экран здесь не трогаем вообще — только гасим
   * свои элементы (счётчик, кнопку «Отменить»), чтобы они не остались
   * висеть в памяти экрана подбора на будущее.
   */
  function соперникНайден(моёПоколение) {
    if (!свериться(моёПоколение)) return;
    остановитьСчётчик();
    показатьКнопкуБота(false, false);
    показатьКнопкуОтмена(false);
    показатьСообщение('');
  }

  function крутитьОжидание(моёПоколение) {
    if (!свериться(моёПоколение)) return;
    if (!window.Сеть || typeof window.Сеть.подождатьСоперника !== 'function') {
      итогНеВышел(моёПоколение, 'Игра не знает, как искать соперника — обновите страницу.');
      return;
    }
    window.Сеть.подождатьСоперника().then(function (итог) {
      if (!свериться(моёПоколение)) return;
      if (!итог || итог.статус === 'отменено') return;
      if (итог.статус === 'свели') { соперникНайден(моёПоколение); return; }
      if (итог.статус === 'ошибка') { итогНеВышел(моёПоколение, итог.причина); return; }
      крутитьОжидание(моёПоколение);   // «ждём» — спрашиваем снова
    });
  }

  function начатьПодбор(моёПоколение) {
    if (!window.Сеть || typeof window.Сеть.встатьВОчередь !== 'function') {
      итогНеВышел(моёПоколение, 'Игра не знает, как искать соперника — обновите страницу.');
      return;
    }
    window.Сеть.встатьВОчередь({ переводной: переводнойИзПамяти() }).then(function (итог) {
      if (!свериться(моёПоколение)) return;
      if (!итог) { итогНеВышел(моёПоколение, 'Сервер игры не ответил.'); return; }
      if (итог.статус === 'свели') { соперникНайден(моёПоколение); return; }
      if (итог.статус === 'ошибка') { итогНеВышел(моёПоколение, итог.причина); return; }
      // Очередь ответила «ждём» — теперь есть что забирать у очереди, кнопка оживает.
      показатьКнопкуБота(true, true);
      крутитьОжидание(моёПоколение);   // «ждём»
    });
  }

  /* -------------------------------------------------------------------
     Действия
     ------------------------------------------------------------------- */

  /** Куда вести после «Отменить»/«Назад». Пришли со списка открытых
      столов (js/открытые-столы.js) — зовём его вернуться(): та же секция
      показывается заново и опрос списка запускается заново, иначе он
      остаётся замороженным (проверка tests/найти-игру-гасит-опрос-
      столов.js). Простой показатьЭкран(откудаПришли) лишь переключает
      видимость и опрос не трогает — для остальных экранов (лобби и т.п.)
      этого достаточно, там опрашивать нечего. */
  function вернутьсяОткудаПришли() {
    if (откудаПришли === 'экран-открытые-столы' &&
        window.ЭкранОткрытыхСтолов &&
        typeof window.ЭкранОткрытыхСтолов.вернуться === 'function') {
      window.ЭкранОткрытыхСтолов.вернуться();
      return;
    }
    показатьЭкран(откудаПришли);
  }

  /** «Играть с ботом»: просим сервер убрать нас из очереди и посадить с ботом.
      Кнопку гасим до ответа. Не вышло, а мы всё ещё в очереди — показываем
      причину, кнопку возвращаем и снова ждём живого соперника. */
  function нажалиСБотом() {
    if (!window.Сеть || typeof window.Сеть.подобратьСБотом !== 'function') {
      показатьСообщение('Игра не знает, как посадить с ботом — обновите страницу.');
      return;
    }
    const моёПоколение = поколение;
    показатьКнопкуБота(true, false);
    показатьСообщение('');
    window.Сеть.подобратьСБотом().then(function (итог) {
      if (!свериться(моёПоколение)) return;
      if (итог && итог.статус === 'свели') { соперникНайден(моёПоколение); return; }
      if (итог && итог.статус === 'ждём') {
        показатьСообщение(итог.причина || '');
        показатьКнопкуБота(true, true);
        /* Обычно запрос бота гасит опрос — заводим его заново. Но если сеть
           до сервера не ходила (опросЖив: тихий повтор ещё летит), свой круг
           ожидания жив, и второй круг слал бы два опроса разом. */
        if (!итог.опросЖив) крутитьОжидание(моёПоколение);
        return;
      }
      // Поиск отменён — экран уже ушёл по «Отменить», рисовать тут нечего.
      if (итог && итог.статус === 'отменено') return;
      итогНеВышел(моёПоколение, итог && итог.причина);
    });
  }

  function нажалиОтменить() {
    остановитьСчётчик();
    показатьКнопкуБота(false, false);
    показатьКнопкуОтмена(false);
    написатьОжидание('Отменяем…');
    поколение++;   // всё, что ещё летит, теперь устарело
    if (window.Сеть && typeof window.Сеть.отменитьПодбор === 'function') {
      window.Сеть.отменитьПодбор();
    }
    вернутьсяОткудаПришли();
  }

  /** «Назад» видна после неудачи, но «не вышло» на экране не всегда значит,
      что сервер нас забыл: мог лететь тихий повтор или запрос бота, и
      запись в очереди жила бы до минуты — хватит, чтобы выбросить игрока
      из лобби в партию. Отмена дешёвая: нет ключа ожидания — запроса
      к серверу нет, только старые ответы помечаются устаревшими. */
  function назад() {
    поколение++;
    if (window.Сеть && typeof window.Сеть.отменитьПодбор === 'function') {
      window.Сеть.отменитьПодбор();
    }
    вернутьсяОткудаПришли();
  }

  /** Открыть экран «Играть онлайн» — одна дверь наружу. */
  function открыть() {
    const было = текущийЭкран();
    if (было !== ЭКРАН) откудаПришли = было;
    убедитьсяЧтоЭкранЕсть();
    показатьСообщение('');
    /* Кнопка видна сразу, но нажать её можно только после ответа очереди
       «ждём» (см. начатьПодбор): раньше у сети нет ключа ожидания, и
       нажатие дало бы «Подбор не запущен», а поиск шёл бы дальше в фоне. */
    показатьКнопкуБота(true, false);
    показатьКнопкуОтмена(true);
    показатьКнопкуНазад(false);
    показатьЭкран(ЭКРАН);
    попытатьсяПривязатьСтрелку(нажалиОтменить);
    поколение++;
    запуститьСчётчик();
    начатьПодбор(поколение);
  }

  window.ЭкранПодбора = { открыть: открыть };

})();
