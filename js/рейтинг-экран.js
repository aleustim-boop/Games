  /** Освежить подпись кнопки-триггера и показать/спрятать фильтры дурака. */
  function отметитьИгру(игра) {
    освежитьКнопкуТекущейИгры();
    освежитьЗаголовокЭкрана(игра);
    освежитьПодписьВыбораИгры(игра);
    /* Пары «Правила дурака» и «Состав игроков» — про правила и состав
       игры дурак. У остальных игр им соответствовать нечему, поэтому
       блок просто скрыт, а не показывает чужие слова «Подкидной/Переводной».
       Пара «Круг игроков» сюда больше не входит (см. УЗЕЛ_КРУГ) — она
       нужна любой игре и этим блоком не прячется. */
    const фильтры = узел(УЗЕЛ_ФИЛЬТРЫ);
    if (фильтры) фильтры.classList.toggle('скрыт', игра !== 'дурак');
    /* Мера «Сила игры» при «Все игры» спрятана: сервер честно отдаёт
       её null (складывать силу разных игр никто не просил — решение
       владельца, план «Рейтинг по макету», вопрос B). Если человек
       смотрел «Силу» на другой игре и переключился на «Все игры»,
       переключаем сами на «Очки»: иначе кнопки для возврата уже нет,
       а мера осталась бы на мёртвой вкладке. */
    const мерыБлок = узел('рейтинг-выбор-меры');
    if (мерыБлок) мерыБлок.classList.toggle('скрыт', игра === 'все');
    if (игра === 'все' && мераСейчас === 'сила') мераСейчас = 'очки';
  }

  /** Пометить выбранную меру в переключателе. */
  function отметитьМеру(мера) {
    const пары = [
      ['кнопка-рейтинг-сила', 'сила'],
      ['кнопка-рейтинг-очки', 'очки']
    ];
    for (const [id, чья] of пары) {
      const кнопка = узел(id);
      if (кнопка) кнопка.classList.toggle('кнопка--активная', чья === мера);
    }
  }

  /** Показать другую меру по уже полученному ответу — без нового запроса. */
  function показатьМеру(мера) {
    мераСейчас = мера === 'сила' ? 'сила' : 'очки';
    отметитьМеру(мераСейчас);
    заполнитьОбъяснение();
    // Ответа ещё нет (первый заход или сервер молчит) — ждём, рисовать нечего.
    if (последнийОтвет) нарисовать(видПоОтвету(последнийОтвет, мераСейчас, правилоДляЗапроса(), составДляЗапроса(), кругДляЗапроса()));
  }

  /** Круг игроков — в отличие от правила и состава дурака, имеет смысл
      у любой игры: сервер отдаёт срез друзей по всем играм разом
      (server/рейтинг.js, срезПоВсемИграмПоСписку), план «Рейтинг по
      макету», заход 2. Поэтому, в отличие от «правилоДляЗапроса» и
      «составДляЗапроса», здесь нет проверки «только дурак». */
  function кругДляЗапроса() {
    return кругСейчас;
  }

  /** Пометить выбранный круг игроков в обеих кнопках пары — та же схема,
      что у «отметитьПравило»: кнопки несут одинаковый data-круг. */
  function отметитьКруг(круг) {
    const кнопки = document.querySelectorAll('[data-круг]');
    for (const кнопка of кнопки) {
      const выбран = кнопка.getAttribute('data-круг') === круг;
      кнопка.classList.toggle('переключатель__вариант--выбран', выбран);
      кнопка.setAttribute('aria-checked', выбран ? 'true' : 'false');
    }
  }

  /** Показать другой круг игроков по уже полученному ответу — та же
      чистая перерисовка, что и «показатьПравило»: второй поход на сервер
      не нужен, сервер уже прислал срез «только друзья» тем же ответом. */
  function показатьКруг(круг) {
    кругСейчас = круг === 'друзья' ? 'друзья' : 'все';
    отметитьКруг(кругСейчас);
    /* Список друзей — другой список, и листать его начинают заново:
       порция возвращается к первым десяти строкам. */
    показаноСтрок = ПОРЦИЯ_СПИСКА;
    if (последнийОтвет) нарисовать(видПоОтвету(последнийОтвет, мераСейчас, правилоДляЗапроса(), составДляЗапроса(), кругДляЗапроса()));
  }

  /** Правило имеет смысл только у дурака — у остальных игр всегда null,
      а не то, что осталось выбранным с прошлого раза на вкладке дурака. */
  function правилоДляЗапроса() {
    return играСейчас === 'дурак' ? правилоСейчас : null;
  }

  /** Пометить выбранное правило дурака в обеих кнопках пары — что в статической
      разметке index.html, что в построенной заново (см. «вариантФильтра»):
      обе несут одинаковый data-правило, по нему их и находим. */
  function отметитьПравило(правило) {
    const кнопки = document.querySelectorAll('[data-правило]');
    for (const кнопка of кнопки) {
      const выбрана = кнопка.getAttribute('data-правило') === правило;
      кнопка.classList.toggle('переключатель__вариант--выбран', выбрана);
      кнопка.setAttribute('aria-checked', выбрана ? 'true' : 'false');
    }
  }

  /** Показать другое правило дурака по уже полученному ответу — та же
      чистая перерисовка, что и «показатьМеру»: сервер уже прислал обе
      половины среза одним ответом, второй поход на сервер не нужен. */
  function показатьПравило(правило) {
    правилоСейчас = правило === 'переводной' ? 'переводной' : 'подкидной';
    отметитьПравило(правилоСейчас);
    /* Другое правило — другой срез, и листать его начинают заново:
       порция возвращается к первым десяти строкам. */
    показаноСтрок = ПОРЦИЯ_СПИСКА;
    if (последнийОтвет) нарисовать(видПоОтвету(последнийОтвет, мераСейчас, правилоДляЗапроса(), составДляЗапроса(), кругДляЗапроса()));
  }

  /** Состав имеет смысл только у дурака — у остальных игр всегда null,
      как и «правилоДляЗапроса» (см. её комментарий). */
  function составДляЗапроса() {
    return играСейчас === 'дурак' ? составСейчас : null;
  }

  /** Пометить выбранный состав игроков в обеих кнопках пары — та же схема,
      что у «отметитьПравило»: кнопки несут одинаковый data-состав. */
  function отметитьСостав(состав) {
    const кнопки = document.querySelectorAll('[data-состав]');
    for (const кнопка of кнопки) {
      const выбрана = кнопка.getAttribute('data-состав') === состав;
      кнопка.classList.toggle('переключатель__вариант--выбран', выбрана);
      кнопка.setAttribute('aria-checked', выбрана ? 'true' : 'false');
    }
  }

  /** Показать другой состав игроков по уже полученному ответу — та же
      чистая перерисовка, что и «показатьПравило»: второй поход на сервер
      не нужен, сервер уже прислал обе половины среза одним ответом. */
  function показатьСостав(состав) {
    составСейчас = состав === 'парами' ? 'парами' : 'личный';
    отметитьСостав(составСейчас);
    /* Другой состав — другой срез, и листать его начинают заново:
       порция возвращается к первым десяти строкам. */
    показаноСтрок = ПОРЦИЯ_СПИСКА;
    if (последнийОтвет) нарисовать(видПоОтвету(последнийОтвет, мераСейчас, правилоДляЗапроса(), составДляЗапроса(), кругДляЗапроса()));
  }

  /** Запомнить ответ: про какую игру он и когда получен. */
  function запомнитьОтвет(игра, ответ) {
    последнийОтвет = ответ;
    играОтвета = игра;
    когдаОтвет = Date.now();
  }

  /** Свежий ответ про эту игру, если он уже есть. Иначе null. */
  function готовыйОтвет(игра) {
    if (!последнийОтвет || играОтвета !== игра) return null;
    if (Date.now() - когдаОтвет > СВЕЖЕСТЬ_ОТВЕТА) return null;
    return последнийОтвет;
  }

  /** Забрать таблицу с сервера и показать её. */
  function обновить(игра) {
    играСейчас = валиднаяИгра(игра);
    /* Другая игра — другая таблица, и листать её начинают с начала:
       порция возвращается к первым десяти строкам. */
    показаноСтрок = ПОРЦИЯ_СПИСКА;
    отметитьИгру(играСейчас);
    отметитьМеру(мераСейчас);
    отметитьКруг(кругСейчас);
    отметитьПравило(правилоСейчас);
    отметитьСостав(составСейчас);
    заполнитьОбъяснение();

    /* Витрина спрашивала место этой же дверью минуту назад — её ответ
       годится целиком. Второй поход на сервер дал бы то же самое, только
       с ожиданием перед пустым экраном. */
    const свежий = готовыйОтвет(играСейчас);
    if (свежий) {
      нарисовать(видПоОтвету(свежий, мераСейчас, правилоДляЗапроса(), составДляЗапроса(), кругДляЗапроса()));
      return;
    }

    показатьОжидание();
    /* Ответ про прежнюю игру больше не годится: он про другую таблицу.
       Иначе переключение меры показало бы дурака на вкладке шашек. */
    последнийОтвет = null;

    номерЗапроса += 1;
    const мой = номерЗапроса;
    спроситьТаблицу(играСейчас).then(function (ответ) {
      // Человек успел переключить игру — этот ответ уже не про то, что на экране.
      if (мой !== номерЗапроса) return;
      запомнитьОтвет(играСейчас, ответ);
      нарисовать(видПоОтвету(ответ, мераСейчас, правилоДляЗапроса(), составДляЗапроса(), кругДляЗапроса()));
    });
  }

  /** Открыть экран рейтинга. Одна из двух дверей наружу (вторая — «открытьСчёт»). */
  function открыть(игра) {
    /* Запоминаем, откуда пришли, ДО показа своего экрана — иначе
       «Назад» вернул бы человека на этот же экран рейтинга. */
    const было = текущийЭкран();
    if (было !== ЭКРАН) откудаПришли = было;
    спрятатьОбъяснение();
    убедитьсяЧтоЭкранРейтингаЕсть();
    убедитьсяЧтоЕстьВыборИгры();
    убедитьсяЧтоЕстьШапка();
    вынестиКругИгроков();
    убедитьсяЧтоЕстьНижниеВкладки();
    /* Полосу заполняем здесь, а не в «подключить»: это и есть момент
       открытия экрана (см. комментарий у «заполнитьНижниеВкладки»). */
    заполнитьНижниеВкладки();
    показатьЭкран(ЭКРАН);
    попытатьсяПривязатьСтрелку(назадИзРейтинга);
    обновить(игра || играСейчас);
  }

  /* -------------------------------------------------------------------
     Дверь для витрины: одна строка «вы 7-й из 42»

     Витрина рисуется первой, поэтому здесь всё подчинено одному: не
     заставлять её ждать. Своего запроса к серверу она не делает нарочно —
     вторая копия запроса однажды разошлась бы с этой.

     Место считается ПО ОЧКАМ, а не по силе. Очки есть у каждого, кто
     доиграл хоть одну партию с кем угодно, а сила — только у того, кто
     играл с живыми людьми, и у большинства она пустая. Строка, которая
     у большинства не показывается, витрине бесполезна.
     ------------------------------------------------------------------- */

  /** Превратить ответ сервера в короткий ответ для витрины. */
  function местоПоОтвету(итог) {
    /* Любая беда со связью или адресом — для витрины одно и то же:
       строки не будет. Точный повод кладём рядом, он не мешает. */
    if (итог.беда) return { беда: 'связь', почему: итог.беда };

    const данные = итог.данные || {};
    /* Вне Telegram рейтинг не ведётся вовсе — это НЕ беда, а пусто:
       чинить нечего и возвращаться незачем. Витрина просто промолчит. */
    if (данные.узналиВас !== true) return { место: 0, всего: 0, узналиВас: false };

    const всего = число(данные.всего) || 0;
    if (данные.яВТаблице !== true) return { место: 0, всего: всего };

    const я = чистаяСтрока(данные.я);
    return { место: я.место === null ? 0 : я.место, всего: всего };
  }

  /**
   * Моё место для витрины. Обещание никогда не срывается.
   * Отдаёт { место, всего }, либо { место: 0 }, если партий ещё нет
   * (или игра открыта не в Telegram), либо { беда: 'связь' }.
   */
  function моёМесто(игра) {
    const какая = валиднаяИгра(игра);
    const свежий = готовыйОтвет(какая);
    if (свежий) return Promise.resolve(местоПоОтвету(свежий));

    return спроситьТаблицу(какая, ЖДЁМ_ДЛЯ_ВИТРИНЫ).then(function (ответ) {
      /* Запоминаем даже неудачный ответ — но только удачный переживёт
         проверку свежести с пользой: если человек тут же откроет полный
         экран, тот возьмёт готовое и не пойдёт на сервер второй раз. */
      if (!ответ.беда) запомнитьОтвет(какая, ответ);
      return местоПоОтвету(ответ);
    });
  }

  /* -------------------------------------------------------------------
     Экран «Как я играю» — личный счёт партий, а не общий рейтинг.

     На index.html этот экран (id «экран-рейтинга») целиком в руках
     js/game.js: разметка написана руками, кнопка «Как я играю» на экране
     рекордов открывает его сама, счёт всегда про дурака. Трогать тот код
     нельзя (см. задание) — здесь для index.html ничего не меняется:
     «открытьСчёт» просто нажимает ту же кнопку за вызывающую сторону.

     На страницах шашек, шахмат и нард такого файла нет вовсе. Экран
     строится этим файлом заново, теми же id и классами, что у дурака
     (стили одни на всех — style.css трогать не пришлось), а данные берёт
     из той же двери, что и game.js, — window.Рейтинг (js/telegram.js):
     она уже умеет любую игру по имени («шашки», «шахматы», «нарды»),
     достаточно передать не «дурак», а свою игру страницы.
     ------------------------------------------------------------------- */

  const ЭКРАН_СЧЁТА = 'экран-рейтинга';
  const УЗЕЛ_СЧЁТА_ГЛАВНОЕ = 'рейтинг-главное';
  const УЗЕЛ_СЧЁТА_ПОДПИСЬ = 'рейтинг-подпись';
  const УЗЕЛ_СЧЁТА_ДИНАМИКА = 'рейтинг-динамика';
  const УЗЕЛ_СЧЁТА_ТАБЛИЦА = 'таблица-рейтинга';
  const УЗЕЛ_СЧЁТА_ВОПРОС = 'вопрос-стирания';
  const КНОПКА_СЧЁТА_СТЕРЕТЬ = 'кнопка-стереть-счёт';
  const КНОПКА_СЧЁТА_НАЗАД = 'кнопка-рейтинг-назад';

  /* На сколько пунктов доля за последние партии должна отличаться
     от общей, чтобы ставить стрелку — тот же порог, что у game.js:
     меньше — шум, а не новость. */
  const ЗАМЕТНАЯ_РАЗНИЦА_ДОЛИ_СЧЁТА = 5;
  const СТРОК_В_РАЗРЕЗЕ_СЧЁТА = 6;

  /* Строили ли мы разметку счёта сами (чужая страница). Если да — вся
     обвязка (стереть счёт, «назад») наша; если нет (index.html) — там
     распоряжается game.js, и вторую дверь поверх той же секции не строим. */
  let счётПостроенЗдесь = false;
  let играСчёта = 'дурак';
  let откудаПришлиСчёт = 'экран-меню';
  let стираниеСчётаЗапрошено = false;

  /** Есть ли на этой странице личный счёт вообще — то же условие, что в game.js. */
  function счётДоступен() {
    return typeof window !== 'undefined' && Boolean(window.Рейтинг) &&
      typeof window.Рейтинг.прочитать === 'function';
  }

  /** Слово «партия» по числу: 1 партия, 2 партии, 5 партий. */
  function словоПартийСчёта(сколько) {
    const двеПоследние = сколько % 100;
    const последняя = сколько % 10;
    if (двеПоследние >= 11 && двеПоследние <= 14) return 'партий';
    if (последняя === 1) return 'партия';
    if (последняя >= 2 && последняя <= 4) return 'партии';
    return 'партий';
  }

  function построитьРазметкуСчёта() {
    const хозяин = хозяинЭкранов();
    if (!хозяин) return null;

    const секция = document.createElement('section');
    секция.id = ЭКРАН_СЧЁТА;
    секция.className = 'экран';

    секция.appendChild(заголовокЭкрана('Как я играю'));
    секция.appendChild(абзацСУзлом(УЗЕЛ_СЧЁТА_ГЛАВНОЕ, 'серия'));
    секция.appendChild(абзацСУзлом(УЗЕЛ_СЧЁТА_ПОДПИСЬ, 'подпись'));
    секция.appendChild(контейнер(УЗЕЛ_СЧЁТА_ДИНАМИКА, ''));
    секция.appendChild(контейнер(УЗЕЛ_СЧЁТА_ТАБЛИЦА, 'таблица'));
    секция.appendChild(абзацСУзлом(УЗЕЛ_СЧЁТА_ВОПРОС, 'подпись скрыт'));
    секция.appendChild(кнопкаЭл(КНОПКА_СЧЁТА_СТЕРЕТЬ, 'Стереть счёт партий',
      'кнопка кнопка--мелкая кнопка--стереть', нажатьСтеретьСчётОбщий));
    секция.appendChild(кнопкаЭл(КНОПКА_СЧЁТА_НАЗАД, 'Назад', 'кнопка', назадИзСчёта));

    хозяин.appendChild(секция);
    return секция;
  }

  function убедитьсяЧтоЭкранСчётаЕсть() {
    if (typeof document === 'undefined') return null;
    let секция = document.getElementById(ЭКРАН_СЧЁТА);
    if (секция) return секция;
    секция = построитьРазметкуСчёта();
    if (секция) счётПостроенЗдесь = true;
    return секция;
  }

  function назадИзСчёта() {
    показатьЭкран(откудаПришлиСчёт);
    /* Тот же приём, что в «назадИзРейтинга»: экран «Как я играю» открывает
       вкладка «Профиль» (js/нижние-вкладки.js), он тоже общий и перекрывал
       стрелку страницы снизу — отдаём её обратно, уходя. */
    try {
      if (window.Телеграм && typeof window.Телеграм.вернутьПрежнююСтрелку === 'function') {
        window.Телеграм.вернутьПрежнююСтрелку();
      }
    } catch (сбой) { /* нет двери — не страшно, своя кнопка «Назад» на экране есть */ }
  }

  /** Две верхние строки: крупное число и пояснение под ним. */
  function написатьГлавноеОСчёте(крупно, мелко) {
    const главное = узел(УЗЕЛ_СЧЁТА_ГЛАВНОЕ);
    const подпись = узел(УЗЕЛ_СЧЁТА_ПОДПИСЬ);
    if (главное) главное.textContent = крупно;
    if (подпись) {
      подпись.textContent = мелко;
      подпись.classList.toggle('скрыт', !мелко);
    }
  }

  /** Снять вопрос о стирании: вернуть кнопке обычную подпись и спрятать строку. */
  function сброситьВопросСтиранияСчёта() {
    стираниеСчётаЗапрошено = false;
    const кнопка = узел(КНОПКА_СЧЁТА_СТЕРЕТЬ);
    if (кнопка) {
      кнопка.textContent = 'Стереть счёт партий';
      кнопка.classList.remove('кнопка--стереть-точно');
    }
    const вопрос = узел(УЗЕЛ_СЧЁТА_ВОПРОС);
    if (вопрос) {
      вопрос.textContent = '';
      вопрос.classList.add('скрыт');
    }
  }

  /* Стереть счёт партий — с переспросом: первое нажатие только задаёт
     вопрос, второе стирает. Рекорды счёт не трогает — то же правило,
     что и в game.js (см. «нажатьСтеретьСчёт» там). */
  function нажатьСтеретьСчётОбщий() {
    if (!счётДоступен()) return;
    const кнопка = узел(КНОПКА_СЧЁТА_СТЕРЕТЬ);
    const вопрос = узел(УЗЕЛ_СЧЁТА_ВОПРОС);
    if (!стираниеСчётаЗапрошено) {
      стираниеСчётаЗапрошено = true;
      if (вопрос) {
        вопрос.textContent = 'Стереть счёт партий? Рекорды останутся. ' +
          'Нажмите ещё раз, чтобы стереть, или «Назад», чтобы оставить.';
        вопрос.classList.remove('скрыт');
      }
      if (кнопка) {
        кнопка.textContent = 'Да, стереть';
        кнопка.classList.add('кнопка--стереть-точно');
      }
      return;
    }
    сброситьВопросСтиранияСчёта();
    написатьГлавноеОСчёте('Стираем…', '');
    window.Рейтинг.очистить(играСчёта).then(function (сводка) {
      нарисоватьМойСчётОбщий(сводка);
      const вопрос2 = узел(УЗЕЛ_СЧЁТА_ВОПРОС);
      if (вопрос2) {
        вопрос2.textContent = 'Счёт стёрт. Рекорды на месте.';
        вопрос2.classList.remove('скрыт');
      }
    }, function () {
      написатьГлавноеОСчёте('Счёт не стёрся', 'Попробуйте ещё раз.');
    });
  }

  /** Одна строка словами под крупным числом. */
  function словаОСчётеОбщие(всего) {
    const части = [всего.побед + ' из ' + всего.партий + ' ' + словоПартийСчёта(всего.партий)];
    if (всего.серияСейчас > 1) части.push('сейчас ' + всего.серияСейчас + ' подряд');
    if (всего.лучшаяСерия > 1) части.push('лучшая серия ' + всего.лучшаяСерия);
    return части.join(' · ');
  }

  /** Одна плитка динамики: «последние N» и доля побед со стрелкой. */
  function плиткаДинамикиСчёта(окно, всего) {
    const плитка = document.createElement('span');
    плитка.className = 'рейтинг__окно';
    const разница = окно.доляПобед - всего.доляПобед;
    if (разница >= ЗАМЕТНАЯ_РАЗНИЦА_ДОЛИ_СЧЁТА) плитка.classList.add('рейтинг__окно--лучше');
    else if (разница <= -ЗАМЕТНАЯ_РАЗНИЦА_ДОЛИ_СЧЁТА) плитка.classList.add('рейтинг__окно--хуже');
    плитка.appendChild(ячейка('последние ' + окно.партий, 'рейтинг__окно-подпись'));
    плитка.appendChild(ячейка(окно.доляПобед + '%', 'рейтинг__окно-число'));
    return плитка;
  }

  function нарисоватьДинамикуСчёта(сводка, всего) {
    const блок = узел(УЗЕЛ_СЧЁТА_ДИНАМИКА);
    if (!блок) return;
    очистить(блок);
    if (!сводка || !всего || !всего.партий) return;
    [сводка.заПоследние20, сводка.заПоследние50].forEach(function (окно) {
      if (!окно || !окно.партий || окно.партий >= всего.партий) return;
      блок.appendChild(плиткаДинамикиСчёта(окно, всего));
    });
  }

  /** Одна строка разреза: за что играли, сколько партий и какая доля побед. */
  function строкаСчётаЭлемент(строка) {
    const узелСтроки = document.createElement('div');
    узелСтроки.className = 'таблица__строка рейтинг__строка';
    узелСтроки.appendChild(ячейка(строка.название, 'таблица__очки рейтинг__название'));
    узелСтроки.appendChild(ячейка(строка.партий + ' ' + словоПартийСчёта(строка.партий),
      'таблица__дата рейтинг__партий'));
    узелСтроки.appendChild(ячейка(строка.доляПобед + '% побед', 'таблица__сложность рейтинг__доля'));
    return узелСтроки;
  }

  /** Разрез счёта таблицей: по строке на уровень, стол или соперника.
      Разрез из одной строки не показываем — это уже сказано крупно выше. */
  function разрезВТаблицуСчёта(таблица, заголовок, строки) {
    if (!Array.isArray(строки) || строки.length < 2) return false;
    таблица.appendChild(абзац(заголовок, 'таблица__раздел'));
    строки.slice(0, СТРОК_В_РАЗРЕЗЕ_СЧЁТА).forEach(function (строка) {
      таблица.appendChild(строкаСчётаЭлемент(строка));
    });
    return true;
  }

  /** Показать сводку личного счёта — тот же порядок, что у game.js: сначала
      крупное число, потом строка словами, и только потом подробности. */
  function нарисоватьМойСчётОбщий(сводка) {
    const таблица = узел(УЗЕЛ_СЧЁТА_ТАБЛИЦА);
    if (!таблица) return;
    очистить(таблица);
    нарисоватьДинамикуСчёта(null, null);

    const всего = (сводка && сводка.всего) ? сводка.всего : null;
    if (!всего || !всего.партий) {
      написатьГлавноеОСчёте('Пока ни одной партии', '');
      таблица.appendChild(абзац('Доиграйте партию до конца — и здесь появится ваш счёт: ' +
        'сколько сыграно, сколько выиграно и с кем шло лучше.', 'таблица__пусто'));
      таблица.appendChild(абзац('В счёт идут все законченные партии. Прерванные не считаются.',
        'таблица__пусто'));
      return;
    }

    написатьГлавноеОСчёте('Побед ' + всего.доляПобед + '%', словаОСчётеОбщие(всего));
    нарисоватьДинамикуСчёта(сводка, всего);

    let показали = разрезВТаблицуСчёта(таблица, 'С кем играли', сводка.поСоперникам);
    показали = разрезВТаблицуСчёта(таблица, 'Против каких ботов', сводка.поУровням) || показали;
    показали = разрезВТаблицуСчёта(таблица, 'За какими столами', сводка.поСтолам) || показали;
    if (!показали) {
      таблица.appendChild(абзац('Сыграйте против другого соперника или за другим столом — ' +
        'здесь появится, где у вас выходит лучше.', 'таблица__пусто'));
    }
    if (сводка.начало) {
      таблица.appendChild(абзац('Счёт ведётся с ' + сводка.начало + '.', 'таблица__пусто'));
    }
  }

  function показатьМойСчётОбщий() {
    const таблица = узел(УЗЕЛ_СЧЁТА_ТАБЛИЦА);
    if (!таблица) return;
    нарисоватьДинамикуСчёта(null, null);
    сброситьВопросСтиранияСчёта();
    if (узел(КНОПКА_СЧЁТА_СТЕРЕТЬ)) узел(КНОПКА_СЧЁТА_СТЕРЕТЬ).classList.toggle('скрыт', !счётДоступен());

    if (!счётДоступен()) {
      написатьГлавноеОСчёте('Счёт пока не ведётся', '');
      очистить(таблица);
      таблица.appendChild(абзац('Игра не смогла добраться до хранилища. Играть можно, ' +
        'но партии не запомнятся.', 'таблица__пусто'));
      return;
    }

    написатьГлавноеОСчёте('Минутку…', '');
    очистить(таблица);
    таблица.appendChild(абзац('Считаем партии…', 'таблица__пусто'));
    window.Рейтинг.прочитать(играСчёта).then(нарисоватьМойСчётОбщий).catch(function () {
      написатьГлавноеОСчёте('Счёт не прочитался', 'Попробуйте зайти сюда ещё раз.');
    });
  }

  /**
   * Открыть личный счёт. Вторая из двух дверей наружу.
   *
   * На index.html разметка уже стоит и ею распоряжается game.js — нажимаем
   * его собственную кнопку «Как я играю», а не строим вторую дверь поверх
   * той же секции (счёт там всегда про дурака — это не наше ограничение,
   * а игра.js, трогать который в этой задаче нельзя).
   */
  function открытьСчёт(игра) {
    if (typeof document === 'undefined') return;
    if (document.getElementById(ЭКРАН_СЧЁТА) && !счётПостроенЗдесь) {
      const кнопкаЧужая = document.getElementById('кнопка-мой-счёт');
      if (кнопкаЧужая) { кнопкаЧужая.click(); return; }
    }

    играСчёта = валиднаяИгра(игра);
    const было = текущийЭкран();
    if (было !== ЭКРАН_СЧЁТА) откудаПришлиСчёт = было;
    убедитьсяЧтоЭкранСчётаЕсть();
    показатьЭкран(ЭКРАН_СЧЁТА);
    попытатьсяПривязатьСтрелку(назадИзСчёта);
    показатьМойСчётОбщий();
  }

  /** Объяснение очков при каждом заходе свёрнуто: сначала таблица. */
  function спрятатьОбъяснение() {
    const место = узел(УЗЕЛ_ОБЪЯСНЕНИЕ);
    const кнопка = узел('кнопка-рейтинг-как-считается');
    if (место) место.classList.add('скрыт');
    if (кнопка) кнопка.textContent = 'Как считается';
  }

  function переключитьОбъяснение() {
    const место = узел(УЗЕЛ_ОБЪЯСНЕНИЕ);
    const кнопка = узел('кнопка-рейтинг-как-считается');
    if (!место) return;
    заполнитьОбъяснение();
    const спрятано = место.classList.toggle('скрыт');
    if (кнопка) кнопка.textContent = спрятано ? 'Как считается' : 'Свернуть';
  }

  function нажатие(id, что) {
    const кнопка = узел(id);
    if (кнопка) кнопка.addEventListener('click', что);
  }

  function подключить() {
    /* Кнопку-триггер с названием игры и панель выбора строит не это
       место: они появляются чуть ниже, при первом вызове
       «убедитьсяЧтоЕстьВыборИгры» — что для готовой разметки (index.html),
       что для страницы, где экран строится с нуля. */
    нажатие('кнопка-рейтинг-сила', function () { показатьМеру('сила'); });
    нажатие('кнопка-рейтинг-очки', function () { показатьМеру('очки'); });
    нажатие('кнопка-рейтинг-как-считается', переключитьОбъяснение);
    нажатие('кнопка-рейтинг-игроков-назад', назадИзРейтинга);
    /* Кнопки «Правила дурака» помечены одинаково (data-правило) что
       в статической разметке index.html, что в построенной заново
       («вариантФильтра») — один делегированный слушатель ловит клик
       по обеим, независимо от того, когда и как кнопка появилась
       на странице (готовая разметка стоит уже сейчас, построенная —
       позже, при первом открытии экрана на чужой странице). */
    document.addEventListener('click', function (событие) {
      const цель = событие && событие.target;
      const кнопкаПравило = (цель && typeof цель.closest === 'function') ? цель.closest('[data-правило]') : null;
      if (кнопкаПравило) показатьПравило(кнопкаПравило.getAttribute('data-правило'));
      /* Пара «Состав игроков» помечена своим атрибутом (data-состав) —
         тот же приём, что и у «Правила дурака» чуть выше, но своей меткой,
         потому что код и текст кнопки у этой пары не совпадают
         (см. «вариантФильтраСостав»). */
      const кнопкаСостав = (цель && typeof цель.closest === 'function') ? цель.closest('[data-состав]') : null;
      if (кнопкаСостав) показатьСостав(кнопкаСостав.getAttribute('data-состав'));
      /* Пара «Круг игроков» помечена своим атрибутом (data-круг) — тот же
         приём, что у «Состава игроков» чуть выше. На статической разметке
         (index.html) атрибут появляется только после «оживитьКругИгроков»
         ниже — до этого кнопки disabled и клик до сюда не доходит вовсе. */
      const кнопкаКруг = (цель && typeof цель.closest === 'function') ? цель.closest('[data-круг]') : null;
      if (кнопкаКруг) показатьКруг(кнопкаКруг.getAttribute('data-круг'));
    });
    /* Если разметка уже стоит на странице (index.html) — здесь же меняем
       её ленту кнопок на кнопку-триггер с панелью, не дожидаясь первого
       открытия экрана. На чужой странице разметки ещё нет, функция тихо
       выходит — новую построит и заполнит «открыть». */
    убедитьсяЧтоЕстьВыборИгры();
    /* Пара «Круг игроков» — тоже достройка готовой разметки, тем же
       приёмом (см. «оживитьКругИгроков»): на чужой странице узла ещё
       нет, функция тихо выходит — построит и заполнит «открыть». Вход
       на «Мои друзья» здесь не достраиваем: он больше не часть готовой
       разметки, его строит заново «нарисоватьОчки» при каждой отрисовке
       круга «Друзья». */
    оживитьКругИгроков();
    /* Вынести круг под сегмент и обернуть заголовок в шапку — здесь же,
       для готовой разметки (index.html): на чужой странице узлов ещё нет,
       обе функции тихо выходят и сработают позже, при первом «открыть». */
    вынестиКругИгроков();
    убедитьсяЧтоЕстьШапка();
  }

  /* В браузере подключаемся сразу: файл стоит в конце страницы, разметка
     к этому времени готова. В Node (проверка случаев) страницы нет вовсе. */
  if (typeof document !== 'undefined') {
    подключить();
    window.ЭкранРейтинга = { открыть: открыть, моёМесто: моёМесто, открытьСчёт: открытьСчёт };
  }

  /* Наружу для проверки — только та часть, что решает, ЧТО показывать.
     Она не трогает страницу, поэтому её можно прогнать в Node.
     «заголовокРейтинга» и «подписьВыбораИгры» — из того же теста:
     ни одна из них не трогает DOM, обе принимают имя игры и отдают
     готовую строку (шаг 5 плана «Рейтинг по макету»). «тройкаНаПодиум» —
     туда же: чистая функция без DOM, решает порядок карточек подиума
     2-1-3 (шаг «подиум 2-1-3» того же плана). */
  if (typeof module !== 'undefined' && module.exports) {
    module.exports = {
      видПоОтвету: видПоОтвету,
      заголовокРейтинга: заголовокРейтинга,
      подписьВыбораИгры: подписьВыбораИгры,
      пунктыПанелиИгр: пунктыПанелиИгр,
      тройкаНаПодиум: тройкаНаПодиум
    };
  }

