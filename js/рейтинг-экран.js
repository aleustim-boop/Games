  /**
   * Пара «Круг игроков» на готовой разметке (index.html) до этого этапа
   * стояла заглушкой: обе кнопки — disabled, у «Друзей» ещё и пометка
   * «скоро». Редактировать index.html в этом этапе нельзя (не наш файл —
   * его правит другой этап), поэтому пара оживает прямо здесь, в уже
   * загруженной странице: находим её по подписи группы (aria-label
   * «Круг игроков», она в разметке уже есть), снимаем disabled и пометку,
   * проставляем data-круг — дальше её ловит тот же делегированный
   * обработчик клика, что и построенную заново разметку (см. «подключить»).
   * Кнопки, у которых data-круг уже есть (построенные этим файлом с нуля
   * через «вариантФильтраКруг»), пропускаем — они и так рабочие.
   */
  function оживитьКругИгроков() {
    const обёртка = document.querySelector('[aria-label="Круг игроков"]');
    if (!обёртка) return;
    const коды = ['все', 'друзья'];
    const кнопки = обёртка.querySelectorAll('button');
    for (let индекс = 0; индекс < кнопки.length; индекс++) {
      const кнопка = кнопки[индекс];
      if (кнопка.hasAttribute('data-круг')) continue;
      кнопка.disabled = false;
      кнопка.setAttribute('data-круг', коды[индекс] || 'все');
      const пометка = кнопка.querySelector('.пометка-скоро');
      if (пометка) пометка.remove();
    }
  }

