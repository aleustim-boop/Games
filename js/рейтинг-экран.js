/* =====================================================================
   Рейтинг игроков: общая таблица всех, кто играл.

   Чем этот экран отличается от соседнего «Как я играю». Тот отвечает на
   вопрос «становлюсь ли я играть лучше» и считает всё в самом телефоне.
   Этот отвечает на другой — «где я среди остальных» — и всё берёт
   с сервера, потому что чужие результаты в телефоне взяться неоткуда.

   Одна дверь наружу:
       window.ЭкранРейтинга.открыть('дурак')   // или 'шашки'
   Кнопку, которая её позовёт, вешает не этот файл: разметка меню живёт
   в другом месте и её правит другой человек.

   Главное правило файла: ВСЁ, ЧТО ПРИШЛО С СЕРВЕРА, ВСТАВЛЯЕТСЯ ТЕКСТОМ.
   Имена в таблице пишут живые люди, и в имени может оказаться что угодно —
   хоть кусок разметки. Поэтому здесь нет ни одного innerHTML: строки
   собираются через createElement и textContent. Правило касается и чисел:
   они проходят через проверку «это вообще число?».

   Как файл устроен внутри. Он разделён надвое нарочно:
     — «видПоОтвету» решает, ЧТО показать, и не трогает страницу вовсе.
       Поэтому её можно прогнать в Node и проверить все случаи без браузера;
     — «нарисовать» только рисует готовое решение.
   ===================================================================== */

