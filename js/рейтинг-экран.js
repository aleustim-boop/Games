  /**
   * Один вариант в паре переключателя. По умолчанию — честное «скоро»
   * (disabled, пометка). Пара «Правила дурака» уже ожила — для нёе зовут
   * с «активна = true»: кнопка рабочая, без disabled и без «скоро»,
   * а вместо этого несёт data-правило со своим значением («подкидной»
   * или «переводной»), по которому её найдёт делегированный обработчик
   * клика (см. «подключить») что в этой разметке, что в статической
   * копии на index.html — там та же метка проставлена руками.
   */
  function вариантФильтра(текст, выбран, активна) {
    const кнопка = document.createElement('button');
    кнопка.type = 'button';
    кнопка.className = 'переключатель__вариант' + (выбран ? ' переключатель__вариант--выбран' : '');
    кнопка.setAttribute('role', 'radio');
    кнопка.setAttribute('aria-checked', выбран ? 'true' : 'false');
    кнопка.textContent = текст;
    if (активна) {
      /* Значение — текст кнопки в нижнем регистре: «Подкидной» → «подкидной»,
         «Переводной» → «переводной». Ровно те же слова, что ждёт «решение»
         третьим доводом «правило» — переводить туда-обратно не нужно. */
      кнопка.setAttribute('data-правило', текст.toLowerCase());
    } else {
      кнопка.disabled = true;
      if (!выбран) {
        const пометка = document.createElement('span');
        пометка.className = 'пометка-скоро';
        пометка.textContent = 'скоро';
        кнопка.appendChild(пометка);
      }
    }
    return кнопка;
  }

