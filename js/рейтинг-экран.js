  /**
   * Кнопка с названием текущей игры — открывает панель выбора (см. ниже).
   * Прежняя лента из отдельной кнопки на каждую игру ломалась бы на
   * пятой: кнопки просто перестали влезать в ширину телефона. Работает
   * в обоих случаях: на index.html в контейнере уже стоят написанные
   * руками «Дурак» и «Шашки» — снимаем их и ставим одну кнопку; на
   * чужой странице контейнер только что построен пустым — ставим ту же
   * кнопку сразу. Повторный вызов (см. «открыть») кнопку не дублирует —
   * только освежает её подпись и список пунктов панели.
   */
  function убедитьсяЧтоЕстьВыборИгры() {
    const контейнерИгр = узел(УЗЕЛ_ВЫБОР_ИГРЫ);
    if (!контейнерИгр) return;
    if (!узел(КНОПКА_ТЕКУЩАЯ_ИГРА)) {
      очистить(контейнерИгр);
      контейнерИгр.appendChild(кнопкаЭл(КНОПКА_ТЕКУЩАЯ_ИГРА, '',
        'кнопка кнопка--выбор рейтинг-выбор__кнопка', открытьПанельВыбораИгры));
    }
    убедитьсяЧтоЕстьПанельВыбораИгры();
    освежитьКнопкуТекущейИгры();
  }

  /** Подпись на кнопке-триггере — название игры, что открыта сейчас. */
  function освежитьКнопкуТекущейИгры() {
    const кнопка = узел(КНОПКА_ТЕКУЩАЯ_ИГРА);
    if (!кнопка) return;
    const запись = играПоКлючу(играСейчас);
    кнопка.textContent = запись ? запись.подпись : играСейчас;
  }

  /**
   * Панель выбора игры: строка поиска и вертикальный список из реестра.
   * Строится один раз (проверка по id — тот же приём, что у остальных
   * «убедитьсяЧтоЕсть…» в этом файле): повторный вызов не навешивает
   * вторые обработчики клика на фон, кнопку «Закрыть» и поле поиска.
   * Сам список пунктов здесь не строится — его заполняет
   * «заполнитьСписокИгр» при каждом открытии, там же и сброс поиска.
   */
  function убедитьсяЧтоЕстьПанельВыбораИгры() {
    if (узел(УЗЕЛ_ПАНЕЛЬ_ИГР)) return;
    const хозяин = хозяинЭкранов();
    if (!хозяин) return;

    const панель = контейнер(УЗЕЛ_ПАНЕЛЬ_ИГР, 'рейтинг-панель-игр скрыт');

    const фон = рамка('рейтинг-панель-игр__фон');
    фон.addEventListener('click', закрытьПанельВыбораИгры);
    панель.appendChild(фон);

    const окно = рамка('рейтинг-панель-игр__окно');

    const шапка = рамка('рейтинг-панель-игр__шапка');
    const поле = document.createElement('input');
    поле.type = 'search';
    поле.id = УЗЕЛ_ПАНЕЛЬ_ИГР_ПОИСК;
    поле.className = 'рейтинг-панель-игр__поиск';
    поле.placeholder = 'Найти игру';
    /* Регистр и кириллица — забота «заполнитьСписокИгр» (toLowerCase
       понимает русские буквы не хуже латинских, второй проверки не надо). */
    поле.addEventListener('input', function () { заполнитьСписокИгр(поле.value); });
    шапка.appendChild(поле);
    шапка.appendChild(кнопкаЭл(КНОПКА_ПАНЕЛЬ_ИГР_ЗАКРЫТЬ, 'Закрыть',
      'кнопка кнопка--мелкая рейтинг-панель-игр__закрыть', закрытьПанельВыбораИгры));
    окно.appendChild(шапка);

    окно.appendChild(контейнер(УЗЕЛ_ПАНЕЛЬ_ИГР_СПИСОК, 'рейтинг-панель-игр__список'));
    окно.appendChild(абзацСУзлом(УЗЕЛ_ПАНЕЛЬ_ИГР_ПУСТО, 'подпись рейтинг-панель-игр__пусто скрыт', 'Такой игры пока нет'));

    панель.appendChild(окно);
    хозяин.appendChild(панель);

    document.addEventListener('keydown', function (событие) {
      if (событие.key === 'Escape' && панельВыбораИгрыОткрыта()) закрытьПанельВыбораИгры();
    });
  }

  /** Панель сейчас видна или спрятана. */
  function панельВыбораИгрыОткрыта() {
    const панель = узел(УЗЕЛ_ПАНЕЛЬ_ИГР);
    return Boolean(панель) && !панель.classList.contains('скрыт');
  }

  /**
   * Список пунктов панели по тексту поиска. Без текста — все игры
   * реестра. Поиск ищет по русской подписи независимо от регистра:
   * «Шахматы», «шахматы» и «ШАХМАТЫ» находят одно и то же.
   */
  function заполнитьСписокИгр(текстПоиска) {
    const список = узел(УЗЕЛ_ПАНЕЛЬ_ИГР_СПИСОК);
    const пусто = узел(УЗЕЛ_ПАНЕЛЬ_ИГР_ПУСТО);
    if (!список) return;
    очистить(список);
    const запрос = String(текстПоиска || '').trim().toLowerCase();
    const найдены = РЕЕСТР_ИГР.filter(function (и) {
      return !запрос || и.подпись.toLowerCase().indexOf(запрос) !== -1;
    });
    найдены.forEach(function (и) {
      const активна = и.ключ === играСейчас;
      список.appendChild(кнопкаЭл('рейтинг-панель-игр-пункт-' + и.ключ, и.подпись,
        'рейтинг-панель-игр__пункт' + (активна ? ' рейтинг-панель-игр__пункт--активна' : ''),
        function () { выбратьИгруИзПанели(и.ключ); }));
    });
    if (пусто) пусто.classList.toggle('скрыт', найдены.length > 0);
  }

  /** Открыть панель: сбросить прежний поиск и построить полный список заново. */
  function открытьПанельВыбораИгры() {
    убедитьсяЧтоЕстьПанельВыбораИгры();
    const панель = узел(УЗЕЛ_ПАНЕЛЬ_ИГР);
    const поле = узел(УЗЕЛ_ПАНЕЛЬ_ИГР_ПОИСК);
    if (!панель) return;
    if (поле) поле.value = '';
    заполнитьСписокИгр('');
    панель.classList.remove('скрыт');
    if (поле) поле.focus();
  }

  /** Закрыть панель — по фону, кнопке «Закрыть», клавише Esc или выбору игры. */
  function закрытьПанельВыбораИгры() {
    const панель = узел(УЗЕЛ_ПАНЕЛЬ_ИГР);
    if (панель) панель.classList.add('скрыт');
  }

  /** Пункт списка нажат: сменить игру и закрыть панель. */
  function выбратьИгруИзПанели(ключ) {
    закрытьПанельВыбораИгры();
    обновить(ключ);
  }

  /**
   * Системная стрелка Telegram делает тот же шаг, что и кнопка «Назад»
   * на экране (правило сборника, см. js/нарды-экран.js). Дверь общая
   * (js/telegram.js), она сама снимает прежний обработчик — вызывать
   * её ещё раз при следующем открытии экрана не страшно.
   */
  function попытатьсяПривязатьСтрелку(действие) {
    try {
      if (window.Телеграм && typeof window.Телеграм.показатьСтрелку === 'function') {
        window.Телеграм.показатьСтрелку(действие);
      }
    } catch (сбой) {
      /* Нет Telegram — не страшно, на экране есть обычная кнопка «Назад». */
    }
  }

  /** Шаг назад с экрана «Рейтинг» — общий для кнопки и для стрелки Telegram. */
  function назадИзРейтинга() {
    /* Общая дверь возврата живёт в js/game.js (её нет на страницах шашек,
       шахмат и нард — там этот экран строит уже этот файл сам). Если
       дверь есть — заходим ею же, что и стрелка Telegram: иначе у «Назад»
       получаются две разные памяти, и они расходятся после второго
       служебного экрана подряд (нашёл ревьюер). Нет двери — прежнее
       поведение: своя память этого файла. */
    if (typeof window.вернутьсяОткудаПришли === 'function') {
      window.вернутьсяОткудаПришли();
      return;
    }
    показатьЭкран(откудаПришли);
    /* Экран «Рейтинг» — общий, он перекрывал стрелку страницы, с которой
       пришли (см. js/telegram.js, стек «показатьСтрелку»). Уходя, обязаны
       вернуть её обратно — иначе стрелка так и осталась бы делать «назад
       из рейтинга», и второе нажатие било бы в пустоту. Двери может не
       быть (старый Telegram, обычный браузер) — тогда звать нечего. */
    try {
      if (window.Телеграм && typeof window.Телеграм.вернутьПрежнююСтрелку === 'function') {
        window.Телеграм.вернутьПрежнююСтрелку();
      }
    } catch (сбой) { /* нет двери — не страшно, своя кнопка «Назад» на экране есть */ }
  }

