  const ЖДЁМ_ДЛЯ_ВИТРИНЫ = 3000;

  /* Номер последнего запроса. Человек может быстро ткнуть «Шашки», потом
     «Дурак» — и ответы вернутся в обратном порядке. Без этого счётчика
     в таблице дурака оказались бы шашки. */
  let номерЗапроса = 0;

  /* -------------------------------------------------------------------
     Разговор с сервером
     ------------------------------------------------------------------- */

  /* Свой, УПРОЩЁННЫЙ разбор адреса — только на страницах без js/сеть.js
     (сейчас это шахматы и нарды). Полный разбор со спором живого адреса
     с мёртвым и полем для ручного ввода живёт в js/сеть.js целиком —
     тащить его сюда ради одного чтения адреса незачем, да и нельзя:
     этот файл нам не отдан. Здесь — то же самое, чем сеть.js пользуется
     в первую очередь: ссылка на игру, память браузера и запасной адрес
     на своём же компьютере. Ключ памяти («server_address») тот же самый,
     что и в js/сеть.js: адрес один на весь сборник, и если человек уже
     вписывал его на другой странице (дурак, шашки), здесь он найдётся сам. */
  const КЛЮЧ_АДРЕСА_БЕЗ_СЕТИ = 'server_address';
  const АДРЕС_ПО_УМОЛЧАНИЮ_БЕЗ_СЕТИ = 'http://127.0.0.1:8790';
  const СВОЙ_КОМПЬЮТЕР_БЕЗ_СЕТИ = /^(localhost|127\.0\.0\.1|\[::1\])(:\d+)?$/i;

  function адресИзСсылкиБезСети() {
    try {
      const разбор = new URLSearchParams(window.location.search);
      return разбор.get('сервер') || разбор.get('server') || '';
    } catch (сбой) {
      return '';
    }
  }

  function адресИзПамятиБезСети() {
    try {
      return (window.localStorage.getItem(КЛЮЧ_АДРЕСА_БЕЗ_СЕТИ) || '').trim();
    } catch (сбой) {
      return '';
    }
  }

  /* Запасной адрес ведёт «на этот же компьютер» — годится только там, где
     и игра открыта с него (файлом с диска или с localhost). На телефоне
     игрока такой адрес ведёт в никуда, и молчаливая подстановка обернулась
     бы неправдой «сервер не отвечает» вместо честного «адреса не знаем». */
  function запаснойАдресГодитсяБезСети() {
    try {
      if (window.location.protocol === 'file:') return true;
      return СВОЙ_КОМПЬЮТЕР_БЕЗ_СЕТИ.test(window.location.host || '');
    } catch (сбой) {
      return false;
    }
  }

  function адресСерверомБезСети() {
    const изСсылки = адресИзСсылкиБезСети();
    if (изСсылки) return изСсылки;
    const изПамяти = адресИзПамятиБезСети();
    if (изПамяти) return изПамяти;
    return запаснойАдресГодитсяБезСети() ? АДРЕС_ПО_УМОЛЧАНИЮ_БЕЗ_СЕТИ : '';
  }

  /**
   * Адрес сервера. Первым делом спрашиваем js/сеть.js — он умеет и ссылку
   * прочитать, и вписанный руками адрес вспомнить, и решить спор, если
   * адресов несколько. Его на странице может не быть вовсе (шахматы, нарды
   * не подключают этот файл) — тогда решаем сами, попроще (см. выше).
   */
  function адресСервера() {
    try {
      if (window.Сеть && typeof window.Сеть.адрес === 'function') {
        return String(window.Сеть.адрес() || '');
      }
    } catch (сбой) {
      /* сеть.js есть, но споткнулся — переходим к своему разбору ниже */
    }
    try {
      return адресСерверомБезСети();
    } catch (сбой) {
      return '';
    }
  }

  /**
   * Подпись Telegram — строка, которой Telegram удостоверяет, кто мы такие.
   * Только по ней сервер узнаёт человека: назваться чужим именем в теле
   * запроса может кто угодно. Нет подписи (игру открыли в обычном
   * браузере) — уходит пустая строка, и сервер ответит «не узнали вас».
   */
  function подписьTelegram() {
    try {
      const приложение = window.Telegram && window.Telegram.WebApp;
      return (приложение && приложение.initData) || '';
    } catch (сбой) {
      return '';
    }
  }

  /**
   * Что не так с адресом. Возвращает короткое слово-повод или null.
   * Поводы разные нарочно: «игра не знает адреса» и «сервер не отвечает» —
   * это два разных положения дел, и одна надпись на оба уже однажды соврала
   * человеку, у которого сервер прекрасно работал.
   */
  function бедаАдреса(адрес) {
    if (!String(адрес || '').trim()) return 'нет-адреса';
    if (!/^https?:\/\//i.test(адрес)) return 'плохой-адрес';
    return null;
  }

  /**
   * Сходить за таблицей. Обещание никогда не срывается: любая беда
   * возвращается обычным ответом с пометкой, чтобы разбирать её в одном
   * месте — в «видПоОтвету».
   *
   * Что возвращается: { беда: null|'нет-адреса'|'плохой-адрес'|'связь', данные }
   */
  function спроситьТаблицу(игра, сколькоЖдать) {
    const адрес = адресСервера();
    const беда = бедаАдреса(адрес);
    if (беда) return Promise.resolve({ беда: беда, данные: null });

    const управление = typeof AbortController !== 'undefined' ? new AbortController() : null;
    const сторож = setTimeout(function () {
      if (управление) управление.abort();
    }, сколькоЖдать || ЖДЁМ_ОТВЕТ);

    const настройки = {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        /* Быстрый туннель показывает страницу-напоминание вместо ответа,
           если не сказать ему, что запрос машинный. Заголовок взят тот же,
           что у js/сеть.js: свой пропуск тут выдумывать нечего. */
        'bypass-tunnel-reminder': 'true'
      },
      body: JSON.stringify({ игра: игра, initData: подписьTelegram() })
    };
    if (управление) настройки.signal = управление.signal;

    return fetch(адрес + '/рейтинг', настройки)
      .then(function (ответ) {
        return ответ.json().then(
          function (данные) {
            if (!данные || typeof данные !== 'object') return { беда: 'связь', данные: null };
            return { беда: null, данные: данные };
          },
          /* Ответ пришёл, но это не наши данные — за адресом сидит
             какая-то другая программа. Для человека это то же самое,
             что молчание: таблицы нет. */
          function () { return { беда: 'связь', данные: null }; }
        );
      })
      .catch(function () {
        return { беда: 'связь', данные: null };
      })
      .then(function (итог) {
        clearTimeout(сторож);
        return итог;
      });
  }

  /* -------------------------------------------------------------------
     Что показывать: решение отдельно от рисования

     Ниже — единственное место, где решается, какой из случаев перед нами.
     Страницу эта часть не трогает совсем, поэтому её можно прогнать
     в Node и проверить все случаи без браузера.
     ------------------------------------------------------------------- */

  /** Строка таблицы, приведённая к безопасному виду: только текст и числа. */
  function чистаяСтрока(сырая) {
    const строка = (сырая && typeof сырая === 'object') ? сырая : {};
    return {
      место: число(строка.место),
      /* Имени может не быть вовсе (человек в Telegram без имени) —
         тогда говорим это своими словами, а не показываем пустоту. */
      имя: текст(строка.имя) || 'Без имени',
      очки: число(строка.очки),
      побед: число(строка.побед),
      партий: число(строка.партий),
      этоЯ: строка.этоЯ === true
    };
  }

  /** Строка из ответа сервера как текст. Ничего, кроме текста, не пропускаем. */
  function текст(что) {
    if (typeof что === 'string') return что.trim();
    if (typeof что === 'number' && isFinite(что)) return String(что);
    return '';
  }

  /** Число из ответа сервера. Мусор превращается в null, а не в «NaN» на экране. */
  function число(что) {
    /* Пустоту проверяем отдельно и первой: Number(null) — это ноль, и без
       этой проверки отсутствующее место превратилось бы в «0 место». */
    if (что === null || что === undefined || что === '') return null;
    const н = Number(что);
    return isFinite(н) ? н : null;
  }

  /** Список строк таблицы, приведённый к безопасному виду. */
  function чистыйСписок(сырой) {
    if (!Array.isArray(сырой)) return [];
    return сырой.map(чистаяСтрока);
  }

  /**
   * Сколько соседей показывать выше и ниже своей строки.
   *
   * Зачем это считается от ширины экрана. Свою строку мы выделяем тремя
   * признаками сразу, чтобы её находили мгновенно, — но на узком телефоне
   * в список влезает три строки, и при пяти соседях сверху человек видел
   * чужую вершину таблицы, а себя должен был искать прокруткой. Все три
   * признака пропадали впустую. Поэтому чем уже экран, тем короче хвост
   * над своей строкой: на 320 точках она оказывается второй сверху.
   */
  function размерОкна() {
    const ширина = (typeof window !== 'undefined' && Number(window.innerWidth)) || 0;
    if (!ширина) return { сверху: 5, снизу: 5 };      // ширины не знаем (проверка в Node)
    if (ширина <= 360) return { сверху: 1, снизу: 5 };
    if (ширина <= 400) return { сверху: 3, снизу: 5 };
    return { сверху: 5, снизу: 5 };
  }

  /** Обрезать окно так, чтобы своя строка была у самого верха списка. */
  function окноВокругСвоей(строки, окно) {
    const мой = строки.findIndex(function (с) { return с.этоЯ; });
    if (мой === -1) return строки;
    const начало = Math.max(0, мой - окно.сверху);
    const конец = Math.min(строки.length, мой + окно.снизу + 1);
    return строки.slice(начало, конец);
  }

  /**
   * Вид по макету владельца: первая пятёрка лидеров и, если своей строки
   * среди них нет, — она же отдельно внизу списка.
   *
   * На входе — «верхушка» (список от сервера, начиная с первого места)
   * и «я» (своя строка или null, если своих очков ещё нет вовсе).
   * На выходе — { лидеры, мояСтрокаВнизу }: «лидеры» — первые пять строк
   * с достоверно проставленным «этоЯ» (сверяем по месту на случай, если
   * сервер его не проставил именно в верхушке), «мояСтрокаВнизу» — своя
   * строка, если её в лидерах нет, иначе null — макет прямо запрещает
   * показывать себя дважды.
   */
  function лидерыИМояСтрока(верхушка, я) {
    const лидеры = верхушка.slice(0, РАЗМЕР_ПЕРВОЙ_ПЯТЁРКИ).map(function (строка) {
      const своя = строка.этоЯ === true ||
        (Boolean(я) && я.место !== null && строка.место !== null && строка.место === я.место);
      return своя === строка.этоЯ ? строка : Object.assign({}, строка, { этоЯ: своя });
    });
    const яВЛидерах = лидеры.some(function (строка) { return строка.этоЯ; });
    return { лидеры: лидеры, мояСтрокаВнизу: (я && !яВЛидерах) ? я : null };
  }

  /**
   * Тройка сильнейших отдельным блоком под своим окном. Тех, кто уже
   * попал в окно, отсюда убираем: одна и та же строка дважды на экране
   * читается как ошибка.
   */
  function верхушкаБезПовторов(верхушка, показанные) {
    const занятые = new Set(показанные.map(function (с) { return с.место; }));
    return верхушка.filter(function (с) { return с.место !== null && !занятые.has(с.место); });
  }

  /** Строка таблицы силы: те же правила безопасности, другие столбцы. */
  function чистаяСтрокаСилы(сырая) {
    const строка = (сырая && typeof сырая === 'object') ? сырая : {};
    return {
      место: число(строка.место),
      имя: текст(строка.имя) || 'Без имени',
      сила: число(строка.сила),
      партий: число(строка.партий),
      /* «Надёжно» — измерена ли сила по-настоящему или это ещё прикидка.
         Приблизительную помечаем знаком «≈», чтобы её не читали как точную. */
      надёжно: строка.надёжно === true,
      этоЯ: строка.этоЯ === true
    };
  }

  function чистыйСписокСилы(сырой) {
    if (!Array.isArray(сырой)) return [];
    /* Пустышки выбрасываем: строка без места и без силы — это не игрок,
       а мусор в ответе, и на экране она выглядела бы поломкой. */
    return сырой.map(чистаяСтрокаСилы)
      .filter(function (строка) { return строка.место !== null || строка.сила !== null; });
  }

  /** Соперник по последней партии: имя, его сила и кто был сильнее. */
  function чистыйСоперник(сырой) {
    const кто = (сырой && typeof сырой === 'object') ? сырой : {};
    const сравнение = текст(кто.сравнение);
    return {
      имя: текст(кто.имя) || 'Без имени',
      сила: число(кто.сила),
      /* Чужие слова на экран не пускаем: сравнений всего три, и любое
         другое значение превращаем в безобидное «вровень». */
      сравнение: (сравнение === 'сильнее' || сравнение === 'слабее') ? сравнение : 'вровень'
    };
  }

  /**
   * Решить, что человек увидит. На входе — то, что вернул «спроситьТаблицу».
   * На выходе — простой объект, который остаётся только нарисовать:
   *   { случай, главное, крупно, пояснение, фразы, соперники,
   *     подписьТаблицы, столбцы, строки, лидеры, мояСтрокаВнизу, я }
   * «лидеры», «мояСтрокаВнизу» и «я» — вид по макету владельца при мере
   * «очки»: первая пятёрка и своя строка внизу, если её нет среди лидеров
   * (см. «лидерыИМояСтрока»). У меры «сила» этих полей не бывает —
   * там прежний вид со своим окном соседей.
   * где «случай» — одно из:
   *   'нет-адреса', 'плохой-адрес', 'нет-связи', 'не-в-телеграме',
   *   'пусто', 'меня-нет', 'я-в-таблице', 'друзья-нет',
   *   'силы-нет', 'сила-не-измерена', 'сила-приблизительная', 'сила-в-таблице'.
   *
   * Вторым доводом идёт мера: 'сила' (насколько сильно играю) или 'очки'
   * (сколько сыграл и выиграл). Это два разных вопроса и два разных
   * ответа сервера, поэтому и решение для них разное.
   *
   * Пятым доводом — круг игроков: 'все' или 'друзья'. Имеет смысл только
   * у меры 'очки' (сила по кругу не делится, см. «мера === 'сила'» ниже);
   * когда круг — 'друзья', а друзей нет вовсе, решение отвечает отдельным
   * случаем 'друзья-нет' — честной фразой вместо пустой таблицы, с флагом
   * «показатьДобавитьДруга» для кнопки на экране.
   */
  function видПоОтвету(ответ, мера, правило, состав, круг) {
    /* Недостающие поля проставляем в одном месте: так каждой ветке ниже
       можно писать только то, что для неё важно, и рисование при этом
       никогда не наткнётся на «нет такого поля». */
    return Object.assign({
      фразы: [],
      соперники: [],
      подписьТаблицы: '',
      столбцы: 'очки',
      строки: [],
      подписьВторойТаблицы: '',
      второйСписок: [],
      /* Вид по макету владельца — первая пятёрка и своя строка внизу,
         если её нет среди лидеров. У беды со связью и у меры «сила»
         этих полей не бывает вовсе, поэтому дефолт — пусто. */
      лидеры: [],
      мояСтрокаВнизу: null,
      я: null,
      /* Кнопка «Добавить друга» на экране — показываем только когда
         решение ниже прямо попросит (случай 'друзья-нет'). */
      показатьДобавитьДруга: false
    }, решение(ответ, мера === 'сила' ? 'сила' : 'очки', правило, состав, круг));
  }

  function решение(ответ, мера, правило, состав, круг) {
    const итог = ответ || {};

    if (итог.беда === 'нет-адреса') {
      return {
        случай: 'нет-адреса',
        главное: 'Игра не знает, где сервер с рейтингом',
        крупно: false,
        пояснение: 'Рейтинг всех игроков живёт на сервере, а ссылка, по которой ' +
                   'открыли игру, адреса сервера не несёт — постучаться просто ' +
                   'некуда. Это не поломка: откройте игру свежей кнопкой в боте, ' +
                   'и таблица появится. Играть можно и без неё.',
        подписьТаблицы: '',
        строки: [],
        /* Без этого поля беда молча рисовалась бы видом меры «очки» —
           даже если открыта вкладка «Сила игры» (дефолт «очки» задан
           в «видПоОтвету»). Ставим ту меру, которую сейчас смотрит человек. */
        столбцы: мера
      };
    }

    if (итог.беда === 'плохой-адрес') {
      return {
        случай: 'плохой-адрес',
        главное: 'Адрес сервера записан неправильно',
        крупно: false,
        пояснение: 'В адресе сервера нет начала «http://» или «https://», ' +
                   'и по такому адресу игра постучаться не может. Проще всего ' +
                   'открыть игру заново кнопкой в боте — она принесёт верный адрес.',
        подписьТаблицы: '',
        строки: [],
        столбцы: мера
      };
    }

    if (итог.беда === 'связь') {
      return {
        случай: 'нет-связи',
        главное: 'Сервер с рейтингом не отвечает',
        крупно: false,
        пояснение: 'Адрес у игры есть, но по нему сейчас никто не отвечает: ' +
                   'сервер держится на домашнем компьютере и, пока тот не в сети, ' +
                   'таблицу взять неоткуда. Это не поломка — игра работает как ' +
                   'обычно, а рейтинг покажется, когда сервер вернётся.',
        подписьТаблицы: '',
        строки: [],
        столбцы: мера
      };
    }

    const данные = итог.данные || {};

    /* Сервер не узнал человека. Пустую таблицу в этом случае не показываем:
       она была бы и бесполезной (своего места в ней нет), и чужой —
       имена играющих людей незачем показывать постороннему. */
    if (данные.узналиВас !== true) {
      const причина = текст(данные.причина);
      return {
        случай: 'не-в-телеграме',
        главное: 'Рейтинг ведётся по учётной записи Telegram',
        крупно: false,
        пояснение: (причина ? причина + '. ' : '') +
                   'Игра сейчас открыта не в Telegram, а узнать человека ей больше ' +
                   'нечем: любое имя можно написать чужое. Откройте игру внутри ' +
                   'Telegram — кнопкой в боте, — и ваше место появится в таблице. ' +
                   'Партии, сыгранные здесь, в рейтинг не попадут.',
        подписьТаблицы: '',
        строки: [],
        столбцы: мера
      };
    }

    // Спросили про силу — дальше совсем другой разбор, у него свой блок.
    if (мера === 'сила') return видСилы(данные.сила);

    /* Круг «Друзья» — самостоятельная ось, и главная её развилка не
       «какой счёт показать», а «есть ли вообще кого показывать». Друзей
       нет совсем — сервер прислал это явным полем «естьДрузья» (см.
       server/сервер.js), и здесь честная фраза с кнопкой «Добавить
       друга» вместо пустой или чужой таблицы. Проверяем раньше правила
       и состава: у среза «только друзья» их не бывает (сервер строит
       его по общему счёту, см. server/рейтинг.js, срезПоСписку). */
    if (круг === 'друзья') {
      const срезДрузей = (данные.друзья && typeof данные.друзья === 'object') ? данные.друзья : null;
      if (!срезДрузей || срезДрузей.естьДрузья !== true) {
        return {
          случай: 'друзья-нет',
          главное: 'В друзьях пока никого нет',
          крупно: false,
          пояснение: 'Добавьте кого-то в друзья — и здесь появится таблица только среди них.',
          показатьДобавитьДруга: true,
          подписьТаблицы: '',
          строки: [],
          лидеры: [],
          мояСтрокаВнизу: null,
          я: null
        };
      }
    }

    /* Правило и состав — две РАЗНЫЕ оси, и сервер отдаёт их раздельными
       срезами (данные.поПравилу.* и данные.поСоставу.*), а не таблицей
       «правило × состав» — скрещивать их незачем (сочетаний всего четыре,
       но сервер их не считает, это осознанное упрощение штаба). Поэтому
       здесь приоритет: круг «друзья» — показываем срез друзей целиком
       (он уже посчитан по общему счёту, без деления на правило/состав);
       иначе — выбран НЕ-дефолтный состав «парами» — показываем его срез
       целиком (сумму по обоим правилам внутри парных партий); иначе
       (состав дефолтный «личный», или сервер поля не прислал) — фильтр
       работает по правилу, как и раньше. Правила нет, поле не пришло —
       читаем общий срез: так продолжают работать шашки и старые ответы
       сервера. */
    const источник = (круг === 'друзья' && данные.друзья)
      ? данные.друзья
      : (состав === 'парами' && данные.поСоставу && данные.поСоставу.парами)
        ? данные.поСоставу.парами
        : (правило && данные.поПравилу && данные.поПравилу[правило])
          ? данные.поПравилу[правило] : данные;

    const верхушка = чистыйСписок(источник.верхушка);
    const вокругМеня = чистыйСписок(источник.вокругМеня);
    const всего = число(источник.всего) || 0;

    /* Играть ещё никто не начинал. Пустая сетка из заголовков здесь
       выглядела бы поломкой, поэтому сетки нет вовсе — только слова. */
    if (всего <= 0 && !верхушка.length && !вокругМеня.length) {
      return {
        случай: 'пусто',
        главное: 'Здесь пока никто не играл',
        крупно: false,
        пояснение: 'Таблица этой игры ещё пуста. Сыграйте партию до конца — ' +
                   'и вы окажетесь в ней первым.',
        подписьТаблицы: '',
        строки: [],
        лидеры: [],
        мояСтрокаВнизу: null,
        я: null
      };
    }

    /* Человек в Telegram, таблица есть, но его самого в ней нет:
       ни одной доигранной партии. Показываем тройку сильнейших —
       чтобы было видно, куда идти. */
    if (источник.яВТаблице !== true || !вокругМеня.length) {
      return {
        случай: 'меня-нет',
        главное: 'Вас в таблице пока нет',
        крупно: false,
        пояснение: 'В рейтинг попадают после первой доигранной партии — ' +
                   'доиграйте одну, и ваша строка появится здесь сама. ' +
                   'Всего в таблице ' + людейСловами(всего) + '.',
        подписьТаблицы: верхушка.length ? 'Сильнейшие' : '',
        строки: верхушка,
        /* Своей строки ещё нет — только первая пятёрка, без неё внизу. */
        лидеры: лидерыИМояСтрока(верхушка, null).лидеры,
        мояСтрокаВнизу: null,
        я: null
      };
    }

    const я = чистаяСтрока(источник.я);
    const моёОкно = окноВокругСвоей(вокругМеня, размерОкна());
    const сильнейшие = верхушкаБезПовторов(верхушка, моёОкно);
    const поМакету = лидерыИМояСтрока(верхушка, я);
    return {
      случай: 'я-в-таблице',
      главное: я.место === null ? 'Вы в таблице' : (я.место + ' место'),
      крупно: true,
      пояснение: 'Всего в таблице ' + людейСловами(всего) + '. У вас ' + очкамиСловами(я.очки) +
                 ': ' + победамиСловами(я.побед, я.партий) + '.',
      подписьТаблицы: 'Вы и соседи по таблице',
      /* Своё окно идёт первым и коротким: человек пришёл смотреть,
         где он, а не кто первый. Тройка сильнейших — отдельным блоком
         ниже, её листают уже по желанию. */
      строки: моёОкно,
      подписьВторойТаблицы: сильнейшие.length ? 'Сильнейшие' : '',
      второйСписок: сильнейшие,
      /* Вид по макету владельца (карточка «Ваше место» + первая пятёрка):
         своя строка внизу списка, только если её нет среди лидеров. */
      лидеры: поМакету.лидеры,
      мояСтрокаВнизу: поМакету.мояСтрокаВнизу,
      я: я
    };
  }

  /**
   * Вторая мера — сила игры: насколько сильно человек играет, а не сколько
   * он сыграл. Считается по силе соперников: обыграть сильного дороже, чем
   * слабого, и проиграть сильному не так обидно.
   *
   * Главное здесь — не число, а готовые фразы сервера («пояснение» и
   * «словами»). Число, которое молча упало, выглядит наказанием; фраза
   * объясняет, за что. Поэтому фразы показываются всегда, когда пришли.
   */
  function видСилы(сырой) {
    const сила = (сырой && typeof сырой === 'object') ? сырой : null;

    /* Блока силы в ответе нет вовсе. Так бывает, если игра подключена
       к серверу постарше: он про вторую меру ещё не знает. Пустоту
       в этом случае не показываем — говорим прямо. */
    if (!сила) {
      return {
        случай: 'силы-нет',
        главное: 'Сила игры здесь пока не считается',
        крупно: false,
        пояснение: 'Сервер, к которому подключена игра, второй меры ещё не знает. ' +
                   'Посмотрите «Очки за победы» — эта таблица работает.',
        /* Без этого поля решение молча рисовалось видом меры «очки»
           (там дефолт «очки» из «видПоОтвету») — не то, что просил
           человек, открывший вкладку «Сила игры». */
        столбцы: 'сила'
      };
    }

    const моя = (сила.моя && typeof сила.моя === 'object') ? сила.моя : {};
    const всего = число(сила.всего) || 0;
    const значение = число(моя.значение);
    const разброс = число(моя.разброс);
    const место = число(моя.место);
    const надёжно = моя.надёжно === true;
    const есть = моя.есть === true;
    const верхушка = чистыйСписокСилы(сила.верхушка);
    const вокругМеня = чистыйСписокСилы(сила.вокругМеня);

    const фразы = [];

    /* Место и точность. Пока рейтинг приблизительный, места нет вовсе —
       и это нарочно: иначе одна везучая победа поднимала бы новичка
       наверх. Так и объясняем, а не показываем пустое место. */
    if (надёжно && место !== null) {
      фразы.push(место + ' место в таблице силы. Всего в ней ' + людейСловами(всего) + '.');
    }
    if (разброс !== null && есть) {
      фразы.push(надёжно
        ? 'Число может гулять примерно на ±' + округлить(разброс) + '.'
        : 'Пока это прикидка: настоящая сила где-то в пределах ±' + округлить(разброс) + '.');
    }
    /* Счёт партий берём готовой строкой с сервера, а не склеиваем сами.
       Своя склейка тут уже соврала: она складывала только победы
       и поражения, ничьи в неё не входили, и «601 партия: 349 побед,
       251 поражение» не сходилось на глазах у человека. Числа и фраза
       про их сумму должны рождаться в одном месте, иначе разъедутся снова. */
    if (есть) {
      const счёт = текст(моя.счёт);
      if (счёт) фразы.push(счёт);
    }

    /* Последняя партия: было — стало — почему именно столько. Это самая
       нужная часть для того, кто только что проиграл. */
    let соперники = [];
    const партия = (сила.последняяПартия && typeof сила.последняяПартия === 'object')
      ? сила.последняяПартия : null;
    if (партия) {
      const было = число(партия.было);
      const стало = число(партия.стало);
      const измСловами = текст(партия.изменениеСловами);
      if (было !== null && стало !== null) {
        фразы.push('Последняя партия: ' + округлить(было) + ' → ' + округлить(стало) +
                   (измСловами ? ' (' + измСловами + ')' : ''));
      }
      const словами = текст(партия.словами);
      if (словами) фразы.push(словами);
      соперники = Array.isArray(партия.соперники) ? партия.соперники.map(чистыйСоперник) : [];
    }

    /* Своя строка в таблице есть только у тех, чья сила измерена
       надёжно. У остальных показываем сильнейших — чтобы было видно,
       куда идти. */
    const своиСоседи = окноВокругСвоей(вокругМеня, размерОкна());
    const строки = своиСоседи.length ? своиСоседи : верхушка;
    const подписьТаблицы = своиСоседи.length ? 'Вы и соседи по силе'
                         : (верхушка.length ? 'Сильнейшие' : '');
    /* Сильнейшие — вторым блоком, и только когда своё окно уже показано:
       иначе они и так стоят в главной таблице. */
    const сильнейшие = своиСоседи.length ? верхушкаБезПовторов(верхушка, своиСоседи) : [];
    if (!строки.length) {
      фразы.push('В таблице силы пока никого нет: в неё попадают, когда сила ' +
                 'измерена надёжно, а для этого нужно несколько партий.');
    }

    /* Пояснение сервера — главное, что человек должен прочитать: оно
       написано отдельно для новичка, для вернувшегося после перерыва
       и для того, чья сила измерена. Своими словами его не подменяем. */
    const пояснение = текст(моя.пояснение) ||
      'Сила растёт за победы над сильными и почти не падает за поражение сильному.';

    if (!есть) {
      return {
        случай: 'сила-не-измерена',
        главное: 'Сила ещё не измерена',
        крупно: false,
        пояснение: пояснение,
        фразы: фразы,
        соперники: соперники,
        подписьТаблицы: подписьТаблицы,
        столбцы: 'сила',
        строки: строки,
        подписьВторойТаблицы: сильнейшие.length ? 'Сильнейшие' : '',
        второйСписок: сильнейшие
      };
    }

    return {
      случай: надёжно ? 'сила-в-таблице' : 'сила-приблизительная',
      /* Знак «≈» у приблизительного числа стоит нарочно: без него человек
         читает прикидку как точную оценку и обижается на её скачки. */
      главное: 'Сила ' + (надёжно ? '' : '≈') + (значение === null ? '—' : округлить(значение)),
      крупно: true,
      пояснение: пояснение,
      фразы: фразы,
      соперники: соперники,
      подписьТаблицы: подписьТаблицы,
      столбцы: 'сила',
      строки: строки,
      подписьВторойТаблицы: сильнейшие.length ? 'Сильнейшие' : '',
      второйСписок: сильнейшие
    };
  }

  /* Ниже — три помощника, которые превращают числа в человеческую речь.
     Нужны они ради падежей: «1 игрок», «2 игрока», «5 игроков». */

  function падеж(сколько, один, два, много) {
    const н = Math.abs(Number(сколько) || 0) % 100;
    const последняя = н % 10;
    if (н > 10 && н < 20) return много;
    if (последняя > 1 && последняя < 5) return два;
    if (последняя === 1) return один;
    return много;
  }

  function людейСловами(сколько) {
    const н = Number(сколько) || 0;
    return н + ' ' + падеж(н, 'игрок', 'игрока', 'игроков');
  }

  function очкамиСловами(очки) {
    if (очки === null) return 'очки ещё не посчитаны';
    return округлить(очки) + ' ' + падеж(очки, 'очко', 'очка', 'очков');
  }

  function победамиСловами(побед, партий) {
    const п = побед === null ? 0 : побед;
    const всего = партий === null ? 0 : партий;
    return округлить(п) + ' ' + падеж(п, 'победа', 'победы', 'побед') +
           ' в ' + всего + ' ' + падеж(всего, 'партии', 'партиях', 'партиях');
  }

  /** Очки могут быть дробными (ничья в шашках даёт половину). Хвост «,0» не нужен. */
  function округлить(число_) {
    const н = Number(число_) || 0;
    return Number.isInteger(н) ? String(н) : String(Math.round(н * 10) / 10).replace('.', ',');
  }

  /* -------------------------------------------------------------------
     Рисование. Только отсюда трогаем страницу.
     ------------------------------------------------------------------- */

  function узел(id) {
    return document.getElementById(id);
  }

  /** Убрать всё, что нарисовали в прошлый раз. */
  function очистить(место) {
    if (!место) return;
    while (место.firstChild) место.removeChild(место.firstChild);
  }

  /** Абзац с текстом. textContent, а не innerHTML — это и есть защита. */
  function абзац(текстСтроки, класс) {
    const элемент = document.createElement('p');
    элемент.className = класс || 'подпись';
    элемент.textContent = текстСтроки;
    return элемент;
  }

  /** Ячейка строки таблицы. */
  function ячейка(текстЯчейки, класс) {
    const элемент = document.createElement('span');
    элемент.className = класс;
    элемент.textContent = текстЯчейки;
    return элемент;
  }

  /** Шапка таблицы: что означает каждый столбец. У двух мер он разный. */
  function шапкаТаблицы(столбцы) {
    const строка = document.createElement('div');
    строка.className = 'рейтинг-строка рейтинг-строка--шапка';
    строка.appendChild(ячейка('#', 'рейтинг-место'));
    строка.appendChild(ячейка('Игрок', 'рейтинг-имя'));
    строка.appendChild(ячейка(столбцы === 'сила' ? 'Сила' : 'Очки', 'рейтинг-очки'));
    строка.appendChild(ячейка(столбцы === 'сила' ? 'Партий' : 'Побед', 'рейтинг-победы'));
    return строка;
  }

  /**
   * Настоящее фото вместо нарисованного человечка — только для своей
   * строки: Telegram отдаёт мини-аппу фотографию только своего игрока,
   * чужую достать неоткуда. Приём — тот же, что в лобби дурака
   * (js/дурак-путь.js, освежитьАватар): дверь window.Телеграм.фотоИгрока()
   * уже сама фильтрует адрес, второй фильтр здесь не нужен и вреден.
   *
   * Класс ставим, ТОЛЬКО когда картинка И ПРАВДА загрузилась. Браузер
   * принимает строку адреса как значение CSS-переменной, даже если по
   * этому адресу ничего не отвечает — getPropertyValue тогда всё равно
   * скажет «принялось», а кружок останется пустым местом, что хуже
   * нарисованного человечка. Поэтому сперва грузим адрес через
   * new Image(), и класс ставим только в её onload; onerror — тихо
   * ничего, прежний нарисованный кружок остаётся.
   *
   * Список рейтинга перерисовывается на каждое переключение фильтра
   * (мера, круг, вид игры), и строка каждый раз новый узел — тот, что
   * получил эту картинку, к моменту onload может уже быть выброшен из
   * страницы. Проверяем document.body.contains перед тем, как красить,
   * иначе поздний ответ дорисует фото в узел, которого никто не видит,
   * а то и в чужую (новую) строку, если следующий вызов создал такой
   * же div раньше, чем сработал onload — своей памятью последнего
   * подтверждённого адреса такую гонку тоже гасим: если адрес уже
   * проверен загруженным, второй раз сеть не переспрашиваем.
   */
  let последнийЗагруженныйАдресФото = '';
  function поставитьФото(строка) {
    const адрес = String((window.Телеграм && typeof window.Телеграм.фотоИгрока === 'function'
      ? window.Телеграм.фотоИгрока() : '') || '');
    if (!адрес) {
      строка.classList.remove('рейтинг-строка--фото');
      строка.style.removeProperty('--фото-аватара');
      return;
    }
    const показатьЗагруженное = function () {
      строка.style.setProperty('--фото-аватара', 'url("' + адрес + '")');
      const принялось = строка.style.getPropertyValue('--фото-аватара').trim() !== '';
      if (!принялось) {
        строка.classList.remove('рейтинг-строка--фото');
        строка.style.removeProperty('--фото-аватара');
        return;
      }
      строка.classList.add('рейтинг-строка--фото');
    };
    if (адрес === последнийЗагруженныйАдресФото) {
      показатьЗагруженное();
      return;
    }
    const картинка = new Image();
    картинка.onload = function () {
      последнийЗагруженныйАдресФото = адрес;
      if (!document.body.contains(строка)) return;
      показатьЗагруженное();
    };
    картинка.onerror = function () { /* сеть подвела — молча оставляем человечка */ };
    картинка.src = адрес;
  }

  /**
   * Одна строка таблицы. Своя помечается по полю «этоЯ», а не по имени:
   * имена повторяются, и по имени игра однажды подсветила бы тёзку.
   */
  function строкаТаблицы(данные, столбцы) {
    const строка = document.createElement('div');
    строка.className = 'рейтинг-строка' + (данные.этоЯ ? ' рейтинг-строка--я' : '');
    if (данные.этоЯ) поставитьФото(строка);
    /* Номер места нужен ещё и оформлению: по нему первая тройка получает
       кружки цвета медалей — из разметки различить первое место и седьмое
       больше нечем. Кладём сюда УЖЕ ПРОВЕРЕННОЕ число (см. «число»), а не
       то, что прислал сервер: атрибут — не текст на странице, но приходит
       он оттуда же, и правило для него то же самое. Места нет — атрибута
       тоже нет, пустой медали не бывает. */
    if (данные.место !== null) строка.setAttribute('data-место', String(данные.место));
    строка.appendChild(ячейка(данные.место === null ? '—' : String(данные.место), 'рейтинг-место'));
    /* Имя пришло от живого человека. Оно попадает на страницу только
       так — текстом внутри элемента, который создали мы сами. */
    строка.appendChild(ячейка(данные.этоЯ ? данные.имя + ' (вы)' : данные.имя, 'рейтинг-имя'));
    if (столбцы === 'сила') {
      /* Приблизительная сила помечается знаком «≈»: точное с виду число
         рядом с измеренными сбивало бы с толку. */
      строка.appendChild(ячейка(данные.сила === null ? '—'
        : (данные.надёжно ? '' : '≈') + округлить(данные.сила), 'рейтинг-очки'));
      строка.appendChild(ячейка(данные.партий === null ? '—' : String(данные.партий), 'рейтинг-победы'));
      return строка;
    }
    строка.appendChild(ячейка(данные.очки === null ? '—' : округлить(данные.очки), 'рейтинг-очки'));
    строка.appendChild(ячейка(
      (данные.побед === null ? '—' : округлить(данные.побед)) +
      ' / ' + (данные.партий === null ? '—' : данные.партий),
      'рейтинг-победы'));
    return строка;
  }

  /**
   * Соперник по последней партии одной строкой: кто и насколько был силён.
   * Имя приходит от живого человека, поэтому — только текстом.
   */
  function строкаСоперника(кто) {
    const пояснения = {
      'сильнее': 'играл сильнее вас',
      'слабее': 'играл слабее вас',
      'вровень': 'играл вровень с вами'
    };
    const строка = document.createElement('p');
    строка.className = 'подпись рейтинг-соперник рейтинг-соперник--' + кто.сравнение;
    строка.textContent = кто.имя + ' — ' + пояснения[кто.сравнение] +
      (кто.сила === null ? '' : ' (сила ' + округлить(кто.сила) + ')');
    return строка;
  }

  /**
   * Кнопка «Добавить друга» внутри таблицы — показывается только когда
   * круг «Друзья» выбран, а друзей пока нет вовсе (см. «решение», случай
   * 'друзья-нет'). Ведёт сразу на «Добавить друга» (список «с кем
   * играл» с кнопкой добавления) — дверь уже готова в js/друзья-экран.js,
   * этому файлу останется её только позвать. Дверь может быть не
   * подключена (страница без друзья-экран.js) — тогда клик молча ничего
   * не делает, а не роняет экран рейтинга.
   */
  function кнопкаДобавитьДруга() {
    const кнопка = document.createElement('button');
    кнопка.type = 'button';
    кнопка.className = 'кнопка';
    кнопка.textContent = 'Добавить друга';
    кнопка.addEventListener('click', function () {
      if (window.ЭкранДрузей && typeof window.ЭкранДрузей.открытьДобавление === 'function') {
        window.ЭкранДрузей.открытьДобавление();
      }
    });
    return кнопка;
  }

  /** Показать готовое решение из «видПоОтвету». Мера решает, каким видом. */
  function нарисовать(вид) {
    const строкаСверху = узел(УЗЕЛ_МЕСТО);
    const таблица = узел(УЗЕЛ_ТАБЛИЦА);
    const итог = узел(УЗЕЛ_ИТОГ);
    if (!строкаСверху || !таблица) return;

    /* Подкрутку списка каждая мера решает сама (см. комментарии внутри
       «нарисоватьСилу» и «нарисоватьОчки»): у них разное устройство своей
       строки, и одно правило на обе однажды и открыло список уже
       прокрученным там, где скроллить было не нужно. */
    if (вид.столбцы === 'сила') нарисоватьСилу(строкаСверху, таблица, вид, итог);
    else нарисоватьОчки(строкаСверху, таблица, вид, итог);
  }

  /**
   * Строка-пояснение под таблицей: показать текстом или спрятать пустой.
   * Одно место для обеих мер — поэтому переключение туда-обратно никогда
   * не оставляет текст сразу в двух местах: у меры «сила» узел всегда
   * пустой и скрытый (её пояснение живёт внутри таблицы, как и раньше).
   */
  function показатьИтог(итог, текстИтога) {
    if (!итог) return;
    итог.textContent = текстИтога || '';
    итог.classList.toggle('скрыт', !текстИтога);
  }

  /**
   * Мера «сила» — прежний вид, без изменений: строка словами сверху,
   * своё окно соседей первым и тройка сильнейших отдельным блоком ниже.
   * У силы нет ни карточки с кубком, ни первой пятёрки по макету —
   * это отдельный вопрос («насколько сильно» вместо «сколько очков»),
   * и на эталон владельца он не завязан.
   */
  function нарисоватьСилу(строкаСверху, таблица, вид, итог) {
    /* Своё место — крупно, как главное число на экране итога. В остальных
       случаях это обычная строка словами: крупный шрифт для объяснения
       беды только пугает. */
    строкаСверху.className = вид.крупно ? 'серия' : 'подпись';
    строкаСверху.textContent = вид.главное;

    /* Узел-итог у этой меры не используется: пояснение силы рисуется
       первым абзацем внутри таблицы (см. ниже) — прежним, не изменённым
       способом. Если он остался заполненным с меры «очки», скрываем. */
    показатьИтог(итог, '');

    очистить(таблица);
    /* Порядок нарочный: сначала готовая фраза сервера (она объясняет
       главное число), потом подробности числами, потом соперники,
       и только в конце таблица. Кто читать не хочет — увидит число сверху
       и таблицу внизу, остальное ему не мешает. */
    if (вид.пояснение) таблица.appendChild(абзац(вид.пояснение, 'подпись рейтинг-пояснение'));
    if (вид.подписьТаблицы) таблица.appendChild(абзац(вид.подписьТаблицы, 'подпись'));
    if (вид.строки.length) {
      таблица.appendChild(шапкаТаблицы(вид.столбцы));
      for (const строка of вид.строки) таблица.appendChild(строкаТаблицы(строка, вид.столбцы));
    }
    /* Тройка сильнейших — вторым блоком, ПОД своим окном. Раньше она
       стояла первой, и на узком телефоне человек видел чужую вершину,
       а себя должен был искать прокруткой. «Где я» важнее, чем «кто
       первый»: наверх листают по желанию, себя ищут всегда. */
    if (вид.второйСписок.length) {
      if (вид.подписьВторойТаблицы) таблица.appendChild(абзац(вид.подписьВторойТаблицы, 'подпись'));
      for (const строка of вид.второйСписок) таблица.appendChild(строкаТаблицы(строка, вид.столбцы));
    }
    /* Подробности — под таблицей, а не над ней. Раньше они стояли выше,
       и на узком телефоне восемь строк текста сдвигали таблицу за нижний
       край: человек открывал рейтинг и не видел ни одной строки, включая
       свою. Наверху остаётся одно главное число и одна фраза, которая
       его объясняет; всё остальное читают, уже увидев своё место. */
    for (const фраза of вид.фразы) таблица.appendChild(абзац(фраза));
    for (const кто of вид.соперники) таблица.appendChild(строкаСоперника(кто));

    /* Здесь список — «окно вокруг своей строки» (см. «окноВокругСвоей»):
       своя строка стоит там, где её поставил сервер, а перед ней ещё
       и лежат пояснение с подписью таблицы. На тесном телефоне это легко
       уводит её за нижний край видимой части — поэтому подкрутка нужна:
       без неё человек открывает свой же рейтинг и не видит себя. */
    подкрутитьКСвоейСтроке(таблица);
  }

  /**
   * Мера «очки» — вид по макету владельца (эталон/дурак-06-рейтинг.png):
   * карточка «Ваше место» с кубком, именем и очками, под ней первая
   * пятёрка лидеров и, если нужно, своя строка внизу списка.
   */
  function нарисоватьОчки(строкаСверху, таблица, вид, итог) {
    очистить(строкаСверху);
    if (вид.я) {
      строкаСверху.className = (вид.крупно ? 'серия' : 'подпись') + ' рейтинг__карточка';
      строкаСверху.appendChild(карточкаТекст(вид));
      строкаСверху.appendChild(карточкаОчки(вид.я));
    } else {
      /* Своих очков ещё нет или пришла беда со связью — карточка честной
         фразой, без выдуманных имени и числа. */
      строкаСверху.className = вид.крупно ? 'серия' : 'подпись';
      строкаСверху.textContent = вид.главное;
    }

    очистить(таблица);
    /* Круг «Друзья» без единого друга — вместо пустой таблицы кнопка,
       которая ведёт прямо на «Добавить друга» (см. «решение», случай
       'друзья-нет'). Лидеров и своей строки здесь всё равно не будет —
       решение прислало их пустыми. */
    if (вид.показатьДобавитьДруга) таблица.appendChild(кнопкаДобавитьДруга());
    for (const строка of вид.лидеры) таблица.appendChild(строкаТаблицы(строка, 'очки'));
    /* Своя строка — только если её нет среди лидеров: макет прямо
       запрещает показывать себя дважды (см. «лидерыИМояСтрока»). */
    if (вид.мояСтрокаВнизу) таблица.appendChild(строкаТаблицы(вид.мояСтрокаВнизу, 'очки'));
    /* Пояснение — отдельным узлом ПОД таблицей, тихой подписью, ближе
       к кнопке «Как считается». Не внутри #рейтинг-таблица: та область
       прокручиваемая, и на узком телефоне предложение обрывалось нижним
       краем списка на полуслове, а раньше (когда стояло первым) ещё и
       отодвигало пятёрку лидеров за нижний край экрана. */
    показатьИтог(итог, вид.пояснение);

    /* Тут своя строка не «где-то в окне», а приклеена к готовому месту:
       либо это одна из первой пятёрки, либо последняя строка списка
       (см. «лидерыИМояСтрока») — и то и другое видно сразу, без подкрутки.
       Раньше список всё равно подкручивало к своей строке — это было
       нужно, пока таблица показывала окно соседей вокруг тебя, а с новым
       макетом лишь прятало первого лидера под нижним краем карточки
       «Ваше место». Список должен открываться с самого верха. */
    таблица.scrollTop = 0;
  }

  /**
   * Левая часть карточки места: тихая подпись «Ваше место» сверху,
   * под ней «128 место» и имя игрока. Подпись — первый ребёнок обёртки
   * по макету владельца: без неё крупное число читается само по себе,
   * а не как ответ на вопрос «где я».
   */
  function карточкаТекст(вид) {
    const обёртка = document.createElement('span');
    обёртка.className = 'рейтинг__карточка-текст';
    обёртка.appendChild(ячейка('Ваше место', 'рейтинг__карточка-подпись'));
    обёртка.appendChild(ячейка(вид.главное, 'рейтинг__карточка-заголовок'));
    обёртка.appendChild(ячейка(вид.я.имя, 'рейтинг__карточка-имя'));
    return обёртка;
  }

  /** Правая часть карточки места: крупные очки и подпись «очков». */
  function карточкаОчки(я) {
    const обёртка = document.createElement('span');
    обёртка.className = 'рейтинг__карточка-очки';
    обёртка.appendChild(ячейка(я.очки === null ? '—' : округлить(я.очки), 'рейтинг__карточка-очки-число'));
    обёртка.appendChild(ячейка('очков', 'рейтинг__карточка-очки-подпись'));
    return обёртка;
  }

  /**
   * Показать свою строку, если она всё-таки оказалась ниже края списка.
   *
   * Это страховка поверх короткого окна: экраны бывают ещё уже, шрифт
   * у человека может быть крупнее, а фраза сервера — длиннее нашей.
   * Прокручиваем не к самой строке, а чуть выше — чтобы было видно,
   * что список начинается не с неё.
   */
  function подкрутитьКСвоейСтроке(таблица) {
    try {
      const своя = таблица.querySelector('.рейтинг-строка--я');
      if (!своя || typeof своя.offsetTop !== 'number') return;
      const сверху = своя.offsetTop - таблица.offsetTop;
      const видно = таблица.clientHeight;
      if (!видно) return;
      // Строка и так видна целиком — не дёргаем список без нужды.
      if (сверху + своя.offsetHeight <= таблица.scrollTop + видно) return;
      таблица.scrollTop = Math.max(0, сверху - Math.round(своя.offsetHeight * 1.5));
    } catch (сбой) {
      /* Прокрутка — удобство, а не смысл экрана: не вышло, и ладно. */
    }
  }

