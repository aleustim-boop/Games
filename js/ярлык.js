/* =====================================================================
   Ярлык на рабочий стол: считаем сыгранные партии и один-два раза
   предлагаем человеку добавить игру на главный экран телефона.

   Наружу window.Ярлык:
       партияСыграна(игра)   — +1 к счётчику; повтор в течение 30 с не считается
                               (одна партия может прийти двумя дорогами);
       предложитьЕслиПора()  — если пора, зовёт окно Telegram «Добавить на
                               главный экран»; своей плашки нет;
       состояние()           — копия записи { played, offers, lastOffer, added }
                               (для проверки).

   Файл никого не зовёт сам и ничего не рисует: зовущие пишут
   window.Ярлык?.партияСыграна?.('сапёр') — страница без файла молчит.

   Память — ТОЛЬКО localStorage (ключ home_shortcut), не облако Telegram:
   ярлык живёт на устройстве, на втором телефоне его нет, и облако
   принесло бы чужое «уже предлагали».

   Все обращения к localStorage и Telegram — в try: без Telegram, с
   отключённой памятью или испорченной записью файл молчит, не падая.
   ===================================================================== */
(function () {
  'use strict';

  const КЛЮЧ = 'home_shortcut';
  const МИНИМУМ_ПАРТИЙ = 3;
  const ПОВТОР_МС = 30 * 1000;               // две отметки ближе — одна партия
  const МЕЖДУ_ПРЕДЛОЖЕНИЯМИ_МС = 14 * 24 * 60 * 60 * 1000;
  const МАКСИМУМ_ПРЕДЛОЖЕНИЙ = 2;            // за всю жизнь, не больше

  let времяПоследнейОтметки = 0;
  let подписанНаСобытие = false;

  function пустаяЗапись() {
    return { played: 0, offers: 0, lastOffer: 0, added: false };
  }

  function число(значение) {
    return (typeof значение === 'number' && isFinite(значение) && значение >= 0) ? значение : 0;
  }

  /** Читает запись; испорченное или чужое превращает в чистую запись. */
  function прочитать() {
    try {
      const сырое = window.localStorage.getItem(КЛЮЧ);
      if (!сырое) return пустаяЗапись();
      const разобрано = JSON.parse(сырое);
      if (!разобрано || typeof разобрано !== 'object') return пустаяЗапись();
      return {
        played: число(разобрано.played),
        offers: число(разобрано.offers),
        lastOffer: число(разобрано.lastOffer),
        added: разобрано.added === true
      };
    } catch (_) {
      return пустаяЗапись();
    }
  }

  function записать(запись) {
    try {
      window.localStorage.setItem(КЛЮЧ, JSON.stringify(запись));
    } catch (_) { /* память недоступна — живём без неё */ }
  }

  function веб() {
    try {
      return (window.Telegram && window.Telegram.WebApp) || null;
    } catch (_) {
      return null;
    }
  }

  /** Телеграм сообщил, что ярлык добавлен: больше не предлагаем никогда. */
  function пометитьДобавленным() {
    const запись = прочитать();
    запись.added = true;
    записать(запись);
  }

  /** Подписка на homeScreenAdded; можно звать много раз — подпишется один. */
  function подписатьсяНаСобытие() {
    if (подписанНаСобытие) return;
    try {
      const приложение = веб();
      if (!приложение || typeof приложение.onEvent !== 'function') return;
      приложение.onEvent('homeScreenAdded', пометитьДобавленным);
      подписанНаСобытие = true;
    } catch (_) { /* без события просто не узнаем о добавлении */ }
  }

  function партияСыграна(игра) {
    try {
      подписатьсяНаСобытие();
      const сейчас = Date.now();
      if (времяПоследнейОтметки && сейчас - времяПоследнейОтметки < ПОВТОР_МС) return;
      времяПоследнейОтметки = сейчас;
      const запись = прочитать();
      запись.played += 1;
      записать(запись);
    } catch (_) { /* счётчик не должен ломать игру */ }
  }

  /** Пора ли по записи: хватает партий, не добавлено, лимит и пауза соблюдены. */
  function пораПоЗаписи(запись, сейчас) {
    if (запись.added) return false;
    if (запись.played < МИНИМУМ_ПАРТИЙ) return false;
    if (запись.offers >= МАКСИМУМ_ПРЕДЛОЖЕНИЙ) return false;
    if (запись.offers >= 1 && сейчас - запись.lastOffer < МЕЖДУ_ПРЕДЛОЖЕНИЯМИ_МС) return false;
    return true;
  }

  function предложитьЕслиПора() {
    try {
      подписатьсяНаСобытие();
      const приложение = веб();
      if (!приложение || !приложение.initData) return;
      if (typeof приложение.addToHomeScreen !== 'function') return;
      if (typeof приложение.checkHomeScreenStatus !== 'function') return;
      if (typeof приложение.isVersionAtLeast !== 'function' || !приложение.isVersionAtLeast('8.0')) return;
      if (!пораПоЗаписи(прочитать(), Date.now())) return;

      приложение.checkHomeScreenStatus(function (статус) {
        try {
          // Только 'missed': ярлыка нет и добавить можно. Остальное — не предлагаем.
          if (статус !== 'missed') return;
          // Запись перечитываем: пока ждали ответ, она могла измениться.
          const запись = прочитать();
          const сейчас = Date.now();
          if (!пораПоЗаписи(запись, сейчас)) return;
          запись.offers += 1;
          запись.lastOffer = сейчас;
          записать(запись); // сперва запоминаем, потом зовём окно
          приложение.addToHomeScreen();
        } catch (_) { /* окно не вышло — не страшно */ }
      });
    } catch (_) { /* без Telegram молчим */ }
  }

  function состояние() {
    return прочитать();
  }

  подписатьсяНаСобытие();

  window.Ярлык = {
    партияСыграна: партияСыграна,
    предложитьЕслиПора: предложитьЕслиПора,
    состояние: состояние
  };
})();
