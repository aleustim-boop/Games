    /** Рассадка: «Вы» — первое место, дальше по кругу. Напарник «2 на 2» — напротив. */
    function рассадка() {
      const сколько = игроков();
      const места = [];
      for (let номер = 0; номер < сколько; номер++) {
        let роль = номер === 0 ? 'я' : 'соперник';
        if (выбор.парами && номер === сколько / 2) роль = 'напарник';
        места.push({ номер: номер, роль: роль, подпись: номер === 0 ? 'Вы' : '' });
      }
      return места;
    }

    function сводка() {
      const сколько = игроков();
      const главное = (выбор.переводной ? 'Переводной' : 'Подкидной') + ' · ' +
        (выбор.парами ? '2 на 2' : сколько + ' ' + словоПоЧислу(сколько, 'игрок', 'игрока', 'игроков'));
      let подпись;
      if (выбор.режим === 'друзья') {
        подпись = выбор.парами
          ? 'Двое на двое, напарник напротив'
          : 'Вы и ещё ' + (сколько - 1) + ' ' + словоПоЧислу(сколько - 1, 'игрок', 'игрока', 'игроков');
      } else {
        const ботов = сколько - 1;
        подпись = выбор.парами
          ? 'Вы с ботом-напарником против двух ботов'
          : (ботов === 1 ? 'Вы и бот' : 'Вы и ' + ботов + ' ' + словоПоЧислу(ботов, 'бот', 'бота', 'ботов'));
      }
      return { главное: главное, подпись: подпись };
    }

    /** Варианты каждого выбора — что выбрано, что можно и почему нельзя. */
    function варианты() {
      const сколько = игроков();
      const колода = действующаяКолода();
      const правилаВарианты = ВАРИАНТЫ_ПРАВИЛ.map(function (в) {
        return { ключ: в.ключ, название: в.название, описание: в.описание, карты: в.карты,
                 выбран: (в.ключ === 'переводной') === выбор.переводной };
      });
      const форматы = ФОРМАТЫ.map(function (ф) {
        return { ключ: ф.ключ, название: ф.название, выбран: (ф.ключ === 'парами') === выбор.парами };
      });
      const числа = [];
      for (let число = МИН; число <= МАКС; число++) {
        const можно = !выбор.парами || число === мерки.сколькоВПарах();
        числа.push({ число: число, выбрано: число === сколько, доступно: можно,
                     почему: можно ? '' : почемуЧислоНельзя() });
      }
      const колоды = [36, 52].map(function (размер) {
        const можно = колодаГодится(размер, сколько);
        return { размер: размер, название: размер + ' ' + словоПоЧислу(размер, 'карта', 'карты', 'карт'),
                 выбрана: размер === колода, доступно: можно,
                 почему: можно ? '' : почемуКолодаНеГодится(размер, сколько) };
      });
      const время = ВАРИАНТЫ_ВРЕМЕНИ.map(function (в) {
        return { секунд: в.секунд, название: в.название, выбрано: в.секунд === null,
                 доступно: !в.скоро, скоро: в.скоро, почему: в.скоро ? ПРИЧИНА_ТАЙМЕРА : '' };
      });
      const сложности = СЛОЖНОСТИ.map(function (слово) {
        return { ключ: слово, название: ПОДПИСИ_СЛОЖНОСТИ[слово] || слово, выбрана: слово === выбор.сложность };
      });
      return {
        правила: правилаВарианты,
        форматы: форматы,
        числа: числа,
        // Для друзей колода — сведение, а не выбор: сервер комнаты её не принимает.
        колоды: выбор.режим === 'друзья' ? null : колоды,
        время: время,
        сложности: выбор.режим === 'боты' ? сложности : null
      };
    }

    /** Все слова текущего экрана разом — страница только раскладывает их по местам. */
    function тексты() {
      const номер = ШАГИ.indexOf(экран);
      const режим = РЕЖИМЫ[выбор.режим] || null;
      const шаги = ШАГИ.map(function (имя, i) {
        return { имя: ИМЕНА_ШАГОВ[имя], номер: i + 1,
                 состояние: i < номер ? 'пройден' : (i === номер ? 'текущий' : 'впереди') };
      });
      const колода = действующаяКолода();
      return {
        заголовок: номер === -1 ? ТЕКСТЫ_ЛОББИ.заголовок : ЗАГОЛОВКИ_ШАГОВ[экран],
        пилюляРежима: режим ? режим.пилюля : '',
        шагСтрокой: номер === -1 ? '' : 'Шаг ' + (номер + 1) + ' из ' + ШАГИ.length,
        шаги: шаги,
        кнопка: номер === ШАГИ.length - 1 ? (режим ? режим.кнопкаГотово : '') : 'Далее',
        // Шаг 1: пример перевода — только у переводного.
        примерПеревода: выбор.переводной ? ПРИМЕР_ПЕРЕВОДА : null,
        // Шаг 2.
        подписьЧисла: ПОДПИСЬ_ЧИСЛА,
        подсказкаИгроков: выбор.парами ? подсказкаПар() : '',
        // Шаг 3.
        сводка: сводка(),
        колодаСведением: выбор.режим === 'друзья'
          ? 'Колода: ' + колода + ' ' + словоПоЧислу(колода, 'карта', 'карты', 'карт') +
            ' — её выбирает сама игра по числу игроков'
          : '',
        карточкаБотов: выбор.режим === 'боты' ? КАРТОЧКА_БОТОВ : ''
      };
    }

