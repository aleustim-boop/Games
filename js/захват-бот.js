// «Захват»: бот трёх уровней (ТЗ раздел 11) и послабление первой партии новичка (ТЗ раздел 13).
// Бот видит то же, что игрок на его месте: карту на начало раунда и своё подкрепление.
// Чужих черновиков не читает. Случай приходит только доводом (функция, дающая число от 0 до 1):
// своего случая и своих часов у файла нет — так бот одинаков на сервере, без сети и в проверках.
// Когда звать бота (спящий, ушедший, бот за столом) — решает комната; здесь только само решение.
// Браузер берёт window.ЗахватБот, сервер — require (как файл правил).
(function () {
  'use strict';

  const Правила = (typeof window !== 'undefined' && window.ЗахватПравила)
    ? window.ЗахватПравила
    : require('./захват-правила.js');
  const Карты = (typeof window !== 'undefined' && window.ЗахватКарты)
    ? window.ЗахватКарты
    : require('./захват-карты.js');
  const ЧИСЛА = Правила.ЧИСЛА;

  // ===================================================================
  // Пороги бота (ТЗ 11.1–11.2) — одним объектом. Общие числа игры (задержка ✓,
  // доля «задумался», «в области остаётся 1») берутся из ЧИСЛА правил.
  //   порог — шанс, с которого бот бьёт; порогСтолицыИКрая — по столице и для достройки края;
  //   запас — сколько войск сверх Нужно (min с доступным); ударовНеБольше — null = без предела;
  //   поправка — считать подкрепление хозяина цели; лидер — +ценность целям лидера по очкам.
  // ===================================================================
  const ПОРОГИ = {
    уровни: {
      лёгкий: { порог: 0.5, порогСтолицыИКрая: 0.5, запас: 0, ударовНеБольше: 1,
        поправка: false, лидер: false, переводы: false, задумывается: true, расстановка: 'случайно' },
      обычный: { порог: 0.75, порогСтолицыИКрая: 0.75, запас: 2, ударовНеБольше: 3,
        поправка: false, лидер: false, переводы: true, задумывается: false, расстановка: 'лучшая' },
      сложный: { порог: 0.7, порогСтолицыИКрая: 0.6, запас: 2, ударовНеБольше: null,
        поправка: true, лидер: true, переводы: true, задумывается: false, расстановка: 'столицаИЛучшая' }
    },
    // Ценность цели (11.1): база, +за весь край после взятия, +за столицу, +за цель лидера (только сложный).
    ценность: { база: 1, весьКрай: 3, столица: 4, уЛидера: 2 },
    // Поправка сложного: D + ⌊подкрепление хозяина цели / делитель⌋.
    делительПоправки: 2,
    // Сложный сперва дотягивает свою граничную столицу до ⌈доля × угроза⌉ войск.
    столицаОтУгрозы: 0.6
  };

  // ===================================================================
  // Карта и окрестности
  // ===================================================================

  // Соседство считается один раз на карту: бот зовётся каждый раунд за каждое место.
  const соседствоПоКарте = {};
  function соседиКарты(карта) {
    if (!соседствоПоКарте[карта.ключ]) соседствоПоКарте[карта.ключ] = Карты.соседство(карта);
    return соседствоПоКарте[карта.ключ];
  }

  // Очки места (ТЗ 5): областей + столиц во владении с их весом.
  function очкиМест(партия) {
    const очки = {};
    партия.игроки.forEach(function (к) { очки[к] = 0; });
    партия.хозяева.forEach(function (х, н) {
      if (н > 0 && х !== null && очки[х] !== undefined) очки[х] += ЧИСЛА.очкиЗаОбласть;
    });
    партия.столицы.forEach(function (с) {
      const х = партия.хозяева[с.область];
      if (х !== null && очки[х] !== undefined) очки[х] += ЧИСЛА.очкиЗаСтолицу;
    });
    return очки;
  }

  // Лидеры по очкам: все места с наибольшими очками (при равенстве лидеров несколько).
  function лидерыПоОчкам(партия) {
    const очки = очкиМест(партия);
    const больше = Math.max.apply(null, Object.keys(очки).map(function (к) { return очки[к]; }));
    const лидеры = {};
    Object.keys(очки).forEach(function (к) { if (очки[к] === больше && больше > 0) лидеры[к] = true; });
    return лидеры;
  }

  // Послабление первой партии (ТЗ 13): в 1-м раунде бот не бьёт по новичку и по ничьим рядом с ним.
  // Ключ новичка — поле партия.новичок (его кладёт тот, кто начинает первую партию).
  function запретныеЦели(партия, место, соседи) {
    const запрет = {};
    const новичок = партия.новичок;
    if (!новичок || партия.раунд !== 1 || место === новичок) return запрет;
    партия.хозяева.forEach(function (х, н) {
      if (н === 0 || х !== новичок) return;
      запрет[н] = true;
      (соседи[н] || []).forEach(function (с) { if (партия.хозяева[с] === null) запрет[с] = true; });
    });
    return запрет;
  }

  // Всё, что бот знает о раунде, — одним объектом, чтобы шаги решения не пересчитывали заново.
  function собратьМир(партия, место) {
    const карта = Правила.картаПартии(партия);
    const соседи = соседиКарты(карта);
    const хозяева = партия.хозяева;
    const свои = карта.области
      .map(function (о) { return о.номер; })
      .filter(function (н) { return хозяева[н] === место; });
    function чужая(н) { return хозяева[н] !== место; }
    function враг(н) { return хозяева[н] !== null && хозяева[н] !== место; }
    return {
      партия: партия,
      место: место,
      карта: карта,
      соседи: соседи,
      свои: свои,
      чужая: чужая,
      граница: свои.filter(function (н) { return (соседи[н] || []).some(чужая); }),
      // угроза(A) — сумма войск во вражеских соседях (ничьи не считаются).
      угроза: function (н) {
        return (соседи[н] || []).reduce(function (сумма, с) {
          return сумма + (враг(с) ? партия.войска[с] : 0);
        }, 0);
      },
      запрет: запретныеЦели(партия, место, соседи)
    };
  }

  // ===================================================================
  // Цели и пары (ТЗ 11.1, шаг 2)
  // ===================================================================

  // Ценность цели и Нужно — зависят только от цели, поэтому считаются раз на цель.
  function оценитьЦель(мир, настройка, лидеры, T) {
    const партия = мир.партия;
    const хозяин = партия.хозяева[T];
    let D = партия.войска[T];
    if (настройка.поправка && хозяин !== null) {
      D += Math.floor((партия.подкрепление[хозяин] || 0) / ПОРОГИ.делительПоправки);
    }
    const столица = партия.столицы.some(function (с) { return с.область === T; });
    const край = мир.карта.края.find(function (к) { return к.области.indexOf(T) !== -1; });
    const достроитКрай = !!край && край.области.every(function (о) {
      return о === T || партия.хозяева[о] === мир.место;
    });
    const цели = ПОРОГИ.ценность;
    let ценность = цели.база;
    if (достроитКрай) ценность += цели.весьКрай;
    if (столица) ценность += цели.столица;
    if (настройка.лидер && хозяин !== null && лидеры[хозяин]) ценность += цели.уЛидера;
    const доля = (столица || достроитКрай) ? настройка.порогСтолицыИКрая : настройка.порог;
    return { ценность: ценность, нужно: Правила.нужноПри(доля, D) };
  }

  // Все пары (своя A, соседняя чужая T) в порядке 11.1: ценность ↓, Нужно ↑, номер T ↑, номер A ↑.
  // Запретные цели послабления в список не попадают.
  function собратьПары(мир, настройка) {
    const лидеры = настройка.лидер ? лидерыПоОчкам(мир.партия) : {};
    const оценки = {};
    const пары = [];
    мир.свои.forEach(function (A) {
      (мир.соседи[A] || []).forEach(function (T) {
        if (!мир.чужая(T) || мир.запрет[T]) return;
        if (!оценки[T]) оценки[T] = оценитьЦель(мир, настройка, лидеры, T);
        пары.push({ из: A, в: T, ценность: оценки[T].ценность, нужно: оценки[T].нужно });
      });
    });
    пары.sort(function (а, б) {
      return (б.ценность - а.ценность) || (а.нужно - б.нужно) || (а.в - б.в) || (а.из - б.из);
    });
    return пары;
  }

  // ===================================================================
  // Шаг 1: расстановка подкрепления
  // ===================================================================

  function поставить(черновик, область, сколько) {
    if (сколько <= 0) return;
    черновик.расстановка[область] = (черновик.расстановка[область] || 0) + сколько;
  }

  // Область с наибольшей угрозой; при равенстве — меньший номер (список уже по возрастанию).
  function самаяУгрожаемая(мир, список) {
    let лучшая = список[0];
    список.forEach(function (н) { if (мир.угроза(н) > мир.угроза(лучшая)) лучшая = н; });
    return лучшая;
  }

  // Лёгкий: по одному войску в случайную граничную; одно число случая на каждое войско.
  function расставитьСлучайно(мир, черновик, сколько, случай) {
    const граница = мир.граница;
    for (let и = 0; и < сколько; и++) {
      const номер = Math.min(граница.length - 1, Math.floor(случай() * граница.length));
      поставить(черновик, граница[номер], 1);
    }
  }

  // Сложный: своя столица, если она граничная, дотягивается до ⌈доля × угроза⌉ войск.
  // Отдаёт, сколько поставлено.
  function укрепитьСтолицу(мир, черновик, сколько) {
    const партия = мир.партия;
    const своя = партия.столицы.find(function (с) {
      return с.хозяинНаСтарте === мир.место && партия.хозяева[с.область] === мир.место;
    });
    if (!своя || мир.граница.indexOf(своя.область) === -1) return 0;
    const надоВсего = Math.ceil(ПОРОГИ.столицаОтУгрозы * мир.угроза(своя.область));
    const добавить = Math.max(0, Math.min(сколько, надоВсего - партия.войска[своя.область]));
    поставить(черновик, своя.область, добавить);
    return добавить;
  }

  function расставить(мир, настройка, пары, черновик, случай) {
    let осталось = мир.партия.подкрепление[мир.место] || 0;
    if (осталось <= 0) return;
    // Чужих соседей нет вовсе (вся карта своя) — остаток туда же, куда его кладут правила.
    if (!мир.граница.length) {
      const куда = Правила.кудаОстаток(мир.партия, мир.место, черновик);
      if (куда) поставить(черновик, куда.область, осталось);
      return;
    }
    if (настройка.расстановка === 'случайно') {
      расставитьСлучайно(мир, черновик, осталось, случай);
      return;
    }
    if (настройка.расстановка === 'столицаИЛучшая') осталось -= укрепитьСтолицу(мир, черновик, осталось);
    // «Пары нет» бывает и из-за послабления — тогда в граничную с наибольшей угрозой.
    const куда = пары.length ? пары[0].из : самаяУгрожаемая(мир, мир.граница);
    поставить(черновик, куда, осталось);
  }

  // ===================================================================
  // Шаг 2: удары
  // ===================================================================

  function доступно(мир, черновик, отправлено, A) {
    return мир.партия.войска[A] + (черновик.расстановка[A] || 0) - ЧИСЛА.остаётсяВОбласти - (отправлено[A] || 0);
  }

  function ударить(мир, настройка, пары, черновик) {
    const отправлено = {};
    const целиЗанятые = {};
    let ударов = 0;
    for (let и = 0; и < пары.length; и++) {
      if (настройка.ударовНеБольше !== null && ударов >= настройка.ударовНеБольше) break;
      const пара = пары[и];
      // В одну цель — только из одной области.
      if (целиЗанятые[пара.в]) continue;
      const можно = доступно(мир, черновик, отправлено, пара.из);
      if (можно < пара.нужно) continue;
      const сколько = Math.min(можно, пара.нужно + настройка.запас);
      черновик.приказы.push({ из: пара.из, в: пара.в, сколько: сколько });
      отправлено[пара.из] = (отправлено[пара.из] || 0) + сколько;
      целиЗанятые[пара.в] = true;
      ударов++;
    }
  }

  // ===================================================================
  // Шаг 3: переводы из тыла к фронту
  // ===================================================================

  // Шагов от каждой области до ближайшей чужой (поиск в ширину сразу от всех чужих).
  function шаговДоЧужой(мир) {
    const шагов = {};
    const очередь = [];
    мир.карта.области.forEach(function (о) {
      if (мир.чужая(о.номер)) {
        шагов[о.номер] = 0;
        очередь.push(о.номер);
      }
    });
    for (let и = 0; и < очередь.length; и++) {
      const тут = очередь[и];
      (мир.соседи[тут] || []).forEach(function (с) {
        if (шагов[с] === undefined) {
          шагов[с] = шагов[тут] + 1;
          очередь.push(с);
        }
      });
    }
    return шагов;
  }

  // Своя область без чужих соседей, где войск хотя бы на одно больше обязательного остатка,
  // отправляет всё лишнее в соседнюю свою, ближайшую к чужой; при равенстве — меньший номер.
  function перевести(мир, черновик) {
    const шагов = шаговДоЧужой(мир);
    const остаётся = ЧИСЛА.остаётсяВОбласти;
    мир.свои.forEach(function (A) {
      if (мир.граница.indexOf(A) !== -1) return;
      const войск = мир.партия.войска[A] + (черновик.расстановка[A] || 0);
      if (войск <= остаётся) return;
      let куда = null;
      (мир.соседи[A] || []).forEach(function (с) {
        if (мир.чужая(с) || шагов[с] === undefined) return;
        if (куда === null || шагов[с] < шагов[куда] || (шагов[с] === шагов[куда] && с < куда)) куда = с;
      });
      if (куда !== null) черновик.приказы.push({ из: A, в: куда, сколько: войск - остаётся });
    });
  }

  // ===================================================================
  // Наружу
  // ===================================================================

  function настройкаУровня(уровень) {
    const настройка = ПОРОГИ.уровни[уровень];
    if (!настройка) throw new Error('Нет такого уровня бота: ' + уровень);
    return настройка;
  }

  // Черновик бота за место: { расстановка: {номер: войск}, приказы: [{ из, в, сколько }] } —
  // тот же вид, что принимает Правила.проверитьЧерновик. Партию не меняет.
  // Порядок чисел случая: лёгкий — «задумался?», потом по одному на каждое войско расстановки.
  // Обычный и сложный случай здесь не тянут. Задержку ✓ тянут следом — задержкаСекунд.
  function решить(партия, место, уровень, случай) {
    const настройка = настройкаУровня(уровень);
    if (typeof случай !== 'function') throw new Error('Боту нужен источник случая доводом');
    const черновик = Правила.пустойЧерновик();
    const мир = собратьМир(партия, место);
    // Областей нет — место выбыло, решать нечего.
    if (!мир.свои.length) return черновик;
    const задумался = настройка.задумывается && случай() < ЧИСЛА.лёгкийЗадумываетсяДоля;
    // Нужно зависит только от цели, поэтому «лучшая пара» известна ещё до расстановки.
    const пары = собратьПары(мир, настройка);
    расставить(мир, настройка, пары, черновик, случай);
    if (!задумался) ударить(мир, настройка, пары, черновик);
    if (настройка.переводы) перевести(мир, черновик);
    return черновик;
  }

  // Через сколько секунд после своего мига бот зажигает ✓ (11.2): нижняя граница + число × размах.
  // Тянется последним числом — сразу после решить с тем же источником случая.
  function задержкаСекунд(уровень, случай) {
    настройкаУровня(уровень);
    const граница = ЧИСЛА.задержкаБотаСекунд[уровень];
    return граница[0] + случай() * (граница[1] - граница[0]);
  }

  const ЗахватБот = {
    ПОРОГИ: ПОРОГИ,
    УРОВНИ: Object.keys(ПОРОГИ.уровни),
    решить: решить,
    задержкаСекунд: задержкаСекунд
  };

  if (typeof module !== 'undefined') module.exports = ЗахватБот;
  if (typeof window !== 'undefined') window.ЗахватБот = ЗахватБот;
})();
