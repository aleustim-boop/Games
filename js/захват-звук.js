'use strict';

/* =====================================================================
   ЗАХВАТ — ЗВУК И ВИБРАЦИЯ (ТЗ, раздел 10). Файлов со звуками нет:
   короткие сигналы собираются в браузере через Web Audio API, как у
   шашек (js/шашки-звук.js). Код нарочно повторён, а не вынесен в общий
   файл — так принято в проекте: игры друг от друга не зависят.

   ДВА ПРАВИЛА, КОТОРЫЕ НЕЛЬЗЯ НАРУШАТЬ.

   1. Звук не начинается до первого касания: движок создаётся лениво,
      при первом сигнале, а первый сигнал бывает только внутри нажатия
      (поставил войско, отдал приказ). До нажатия телефон его не даёт.

   2. К динамику ведёт ОДНА дорога — сигнал(): только он смотрит на
      выключатель, и только он зовёт сыграть(), которая создаёт узлы.
      Любой новый звук обязан идти через сигнал(), тогда кнопка «Звук»
      глушит всё разом и обойти её нельзя.

   Вибрацию отдаёт общая дверь Телеграм.отклик() из js/telegram.js: она
   сама смотрит на выключатель «Вибрация» и на версию Telegram. Здесь
   только выбор, какой отклик к какому событию (по таблице ТЗ).

   Наружу: window.ЗахватЗвук — поставить, приказ, отказ, готово, тик,
   раскрытие, удар, захват, потеря, столица, победа, поражение,
   включён(), переключить().
   ===================================================================== */

(function () {
  /* Ключ памяти — латиницей (облако Telegram русские ключи не принимает). */
  var КЛЮЧ_ЗВУКА = 'zahvat-sound';
  var ГРОМКОСТЬ = 0.07;   // тихо: игра часто идёт в наушниках в транспорте
  /* Итог партии звучит с задержкой: последнее раскрытие только что отзвучало,
     и фанфары поверх слились бы в кашу. */
  var ПАУЗА_ПЕРЕД_ИТОГОМ = 0.15;

  var звуковойДвижок = null;

  function прочитатьНастройку() {
    try {
      return window.localStorage.getItem(КЛЮЧ_ЗВУКА);
    } catch (ошибка) {
      return null;   // память запрещена — считаем, что звук включён
    }
  }

  function записатьНастройку(значение) {
    try {
      window.localStorage.setItem(КЛЮЧ_ЗВУКА, значение);
    } catch (ошибка) { /* запрещённая память — не повод ломать игру */ }
  }

  var звукВключён = прочитатьНастройку() !== 'выключен';

  /** Звуковой движок браузера. Создаём при первом звуке: до нажатия его не дают. */
  function получитьЗвуковойДвижок() {
    if (звуковойДвижок) return звуковойДвижок;
    try {
      var Движок = window.AudioContext || window.webkitAudioContext;
      if (!Движок) return null;
      звуковойДвижок = new Движок();
    } catch (ошибка) {
      звуковойДвижок = null;
    }
    return звуковойДвижок;
  }

  /**
   * Создать узлы и сыграть одну ноту. Сюда НЕЛЬЗЯ ходить напрямую —
   * только через сигнал(), который проверяет выключатель.
   *
   * Параметры (все необязательные): тип волны; громкость; дои — частота,
   * к которой нота скользит (для «вжух», «наливания», «ноты вниз»);
   * нарастание — громкость растёт до конца ноты (гул раскрытия).
   * Начало и затухание обязательны: без них слышен щелчок на краях.
   */
  function сыграть(частота, длительность, задержка, параметры) {
    var движок = получитьЗвуковойДвижок();
    if (!движок) return;
    var п = параметры || {};
    try {
      if (движок.state === 'suspended') движок.resume();
      var начало = движок.currentTime + (задержка || 0);
      var конец = начало + длительность;
      var громкостьНоты = п.громкость || ГРОМКОСТЬ;
      var генератор = движок.createOscillator();
      var громкость = движок.createGain();
      генератор.type = п.тип || 'triangle';
      генератор.frequency.setValueAtTime(частота, начало);
      if (п.дои) генератор.frequency.exponentialRampToValueAtTime(п.дои, конец);
      громкость.gain.setValueAtTime(0.0001, начало);
      if (п.нарастание) {
        громкость.gain.exponentialRampToValueAtTime(громкостьНоты, начало + длительность * 0.9);
      } else {
        громкость.gain.exponentialRampToValueAtTime(громкостьНоты, начало + 0.01);
      }
      громкость.gain.exponentialRampToValueAtTime(0.0001, конец);
      генератор.connect(громкость);
      громкость.connect(движок.destination);
      генератор.start(начало);
      генератор.stop(конец + 0.02);
    } catch (ошибка) {
      /* звук — не то, ради чего стоит ронять игру */
    }
  }

  /** ЕДИНСТВЕННАЯ дорога к динамику: выключено — ни одного узла. */
  function сигнал(частота, длительность, задержка, параметры) {
    if (!звукВключён) return;
    сыграть(частота, длительность, задержка, параметры);
  }

  /** Вибрация — через общую дверь; её выключатель живёт в js/telegram.js. */
  function вибро(вид) {
    try {
      if (window.Телеграм && typeof window.Телеграм.отклик === 'function') {
        window.Телеграм.отклик(вид);
      }
    } catch (ошибка) { /* вибрация не повод ронять игру */ }
  }

  /* Виды отклика Телеграм.отклик сопоставлены с силами Telegram так:
     «лёгкий» — impact light, «карта» — impact medium, «взятка» — impact heavy,
     «победа» — notification success, «проигрыш» — notification error,
     «нельзя» — notification warning. Имена исторические (от дурака), берём
     по СИЛЕ из таблицы ТЗ 10, а не по смыслу имени. */

  function звукПоставить() {   // стеклянный «тинь», 40 мс
    сигнал(1568, 0.04, 0, { тип: 'sine' });
    вибро('лёгкий');
  }
  function звукПриказа() {     // мягкий «вжух» вверх, 120 мс
    сигнал(300, 0.12, 0, { тип: 'sine', дои: 700 });
    вибро('карта');
  }
  function звукОтказа() {      // глухой «тук», 60 мс
    сигнал(110, 0.06);
    вибро('проигрыш');
  }
  function звукГотово() {      // две ноты вверх
    сигнал(523, 0.09);
    сигнал(784, 0.14, 0.09);
  }
  function звукТика() {        // тихий тик раз в секунду
    сигнал(1200, 0.02, 0, { тип: 'sine', громкость: 0.03 });
  }
  function звукРаскрытия() {   // низкий нарастающий гул, 600 мс
    сигнал(70, 0.6, 0, { тип: 'sawtooth', дои: 130, нарастание: true, громкость: 0.05 });
  }
  function звукУдара() {       // треск стекла, 150 мс: три быстрых резких щелчка
    сигнал(2400, 0.04, 0, { тип: 'square', громкость: 0.03 });
    сигнал(3300, 0.03, 0.05, { тип: 'square', громкость: 0.03 });
    сигнал(1900, 0.05, 0.10, { тип: 'square', громкость: 0.03 });
  }
  function звукЗахвата() {     // «наливание», нота вверх, 300 мс
    сигнал(440, 0.3, 0, { тип: 'sine', дои: 880 });
    вибро('победа');
  }
  function звукПотери() {      // нота вниз, 250 мс
    сигнал(330, 0.25, 0, { дои: 180 });
    вибро('взятка');
  }
  function звукСтолицы() {     // короткий аккорд, 500 мс
    [523, 659, 784].forEach(function (частота) {
      сигнал(частота, 0.5, 0, { тип: 'sine', громкость: 0.04 });
    });
  }
  function звукПобеды() {      // до-ми-соль
    сигнал(523, 0.12, ПАУЗА_ПЕРЕД_ИТОГОМ);
    сигнал(659, 0.12, ПАУЗА_ПЕРЕД_ИТОГОМ + 0.13);
    сигнал(784, 0.26, ПАУЗА_ПЕРЕД_ИТОГОМ + 0.26);
    вибро('победа');
  }
  function звукПоражения() {   // две ноты вниз
    сигнал(300, 0.16, ПАУЗА_ПЕРЕД_ИТОГОМ);
    сигнал(160, 0.30, ПАУЗА_ПЕРЕД_ИТОГОМ + 0.16);
    вибро('нельзя');
  }

  function переключить() {
    звукВключён = !звукВключён;
    записатьНастройку(звукВключён ? 'включен' : 'выключен');
    if (звукВключён) звукПоставить();   // сразу слышно, что включилось
    return звукВключён;
  }

  window.ЗахватЗвук = {
    поставить: звукПоставить,
    приказ: звукПриказа,
    отказ: звукОтказа,
    готово: звукГотово,
    тик: звукТика,
    раскрытие: звукРаскрытия,
    удар: звукУдара,
    захват: звукЗахвата,
    потеря: звукПотери,
    столица: звукСтолицы,
    победа: звукПобеды,
    поражение: звукПоражения,
    включён: function () { return звукВключён; },
    переключить: переключить
  };
})();
