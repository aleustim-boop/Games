'use strict';

/* =====================================================================
   ШАШКИ — РЕКОРДЫ. Что считается достижением и где оно лежит.

   ЧТО СЧИТАЕМ РЕКОРДОМ. Очков в шашках нет, поэтому рекорд здесь —
   СЕРИЯ ПОБЕД ПОДРЯД, и считается она отдельно на каждом уровне
   соперника. Так решил штаб. Ничья серию не обрывает, но и не
   продолжает: она просто ни на что не влияет.

   ГДЕ ЭТО ЛЕЖИТ. В том же хранилище, что и у дурака (js/telegram.js),
   но за отдельной дверью и под отдельным ключом: у рекордов есть
   имя игры, и для шашек оно своё — «шашки». Поэтому серии шашек
   и серии дурака не складываются в одну кашу, даже когда лежат
   в одном облаке Telegram.

   ПОЧЕМУ НЕ saveScore/loadScore. Эти две функции — договор дурака:
   игру они не спрашивают и всегда пишут в дуракову таблицу. Пока
   в них не появится довод «какая игра», шашки пользуются соседней
   дверью того же файла — window.Рейтинг, у которой имя игры есть
   с самого начала (см. отчёт штабу).

   В ПАРТИЮ ВДВОЁМ ЗА ОДНИМ ТЕЛЕФОНОМ РЕКОРДЫ НЕ ПИШУТСЯ ВОВСЕ.
   Там за доской два человека, и чья победа — сказать нельзя. Записать
   такую партию значит соврать в таблице, а пустая строка честнее.

   Наружу файл отдаёт четыре двери:
     ШашкиРекорды.записатьПартию({исход, уровень}) — вернёт короткую
        подпись для плашки итога («Побед подряд: 3 — это рекорд!»)
     ШашкиРекорды.показать()  — открыть экран рекордов
     ШашкиРекорды.спрятать()  — вернуться к доске
     ШашкиРекорды.открыты()   — виден ли сейчас экран рекордов
   ===================================================================== */

(function () {
  /* Имя игры в хранилище. Ровно это слово знает js/telegram.js: под ним
     он собирает ключ «rating_shashki». Переименуете здесь — рекорды
     игроков останутся под старым именем и на экране пропадут. */
  var ИГРА = 'шашки';

  var УРОВНИ = ['лёгкий', 'обычный', 'сложный'];
  // Уровень в подписи стоит в предложном падеже: «серия на сложном»
  var УРОВЕНЬ_НА = { 'лёгкий': 'лёгком', 'обычный': 'обычном', 'сложный': 'сложном' };
  var СКОЛЬКО_ПАРТИЙ_ПОКАЗЫВАЕМ = 10;

  var экранРекордов = document.getElementById('экран-рекордов');
  var экранДоски = document.getElementById('экран-шашек');
  var экранИтога = document.getElementById('экран-итога');
  var строкаЛучшего = document.getElementById('лучший-рекорд');
  var таблица = document.getElementById('таблица-рекордов-шашек');
  var кнопкаНазад = document.getElementById('кнопка-рекорды-назад');

  /* ------------------------------------------------------------------
     ХРАНИЛИЩЕ
     ------------------------------------------------------------------ */

  /** Есть ли куда писать. Нет — игра всё равно работает, просто без рекордов. */
  function хранилищеГотово() {
    try {
      return !!(window.Рейтинг && window.Рейтинг.готов && window.Рейтинг.готов());
    } catch (ошибка) {
      return false;
    }
  }

  /**
   * Записать законченную партию против робота.
   * что.исход — «победа», «поражение» или «ничья» глазами человека;
   * что.уровень — с каким роботом играли.
   * Обещание никогда не падает: экран итога из-за рекордов сломаться не должен.
   */
  function записатьПартию(что) {
    var исход = (что && что.исход) || '';
    var уровень = (что && что.уровень) || 'обычный';
    if (!хранилищеГотово()) return Promise.resolve('');

    return window.Рейтинг.записатьПартию({
      исход: исход,
      подпись: уровень,      // тем же словом уровень назван в таблице
      игроков: 2,            // за доской всегда двое
      соперники: 'боты',     // партии с людьми по сети в шашках пока нет
      игра: ИГРА
    }).then(function (сводка) {
      return подписьДляПлашки(сводка, уровень, исход);
    }).catch(function () {
      return '';
    });
  }

  /** Строка про уровень из сводки: партии, победы и серии именно на нём. */
  function строкаУровня(сводка, уровень) {
    var строки = (сводка && сводка.поУровням) || [];
    for (var i = 0; i < строки.length; i++) {
      if (строки[i].название === уровень) return строки[i];
    }
    return null;
  }

  /**
   * Что написать на плашке итога.
   * Главное здесь — не хвалить зря: «рекорд» появляется, только когда
   * нынешняя серия и вправду сравнялась с лучшей и в ней больше одной победы.
   */
  function подписьДляПлашки(сводка, уровень, исход) {
    var строка = строкаУровня(сводка, уровень);
    if (!строка) return '';
    var на = УРОВЕНЬ_НА[уровень] || уровень;

    if (исход === 'победа') {
      var подпись = 'Побед подряд на ' + на + ': ' + строка.серияСейчас;
      if (строка.серияСейчас >= 2 && строка.серияСейчас >= строка.лучшаяСерия) {
        подпись += ' — это рекорд!';
      }
      return подпись;
    }

    if (исход === 'ничья') {
      // Ничья серию не обрывает — про это и говорим, иначе человек решит,
      // что счёт сбросился.
      return строка.серияСейчас > 0
        ? 'Ничья серию не прерывает. Побед подряд: ' + строка.серияСейчас
        : 'Ничья. Серия побед не начата';
    }

    if (строка.лучшаяСерия > 0) {
      return 'Серия прервалась. Лучшая на ' + на + ': ' + строка.лучшаяСерия;
    }
    return '';
  }

  /* ------------------------------------------------------------------
     ЭКРАН РЕКОРДОВ
     ------------------------------------------------------------------ */

  function открыты() {
    return !!(экранРекордов && экранРекордов.classList.contains('экран--виден'));
  }

  /* Плашка итога лежит поверх всего (так она и задумана) и, если её не убрать,
     накрывает собой таблицу рекордов вместе с кнопкой «Назад к доске».
     Проверено пальцем: кнопка видна, а нажимается «Играть ещё» под ней.
     Поэтому на время рекордов плашку прячем и помним, что она была. */
  var плашкаИтогаБылаВидна = false;

  function показать() {
    if (!экранРекордов) return;
    // Про плашку запоминаем только при первом открытии: нажали «Рекорды»
    // дважды подряд — во второй раз она уже спрятана нами, и записать «её
    // не было» значило бы потерять её насовсем.
    if (!открыты()) {
      плашкаИтогаБылаВидна = !!(экранИтога && экранИтога.classList.contains('экран--виден'));
    }
    экранРекордов.classList.add('экран--виден');
    if (экранДоски) экранДоски.classList.remove('экран--виден');
    if (плашкаИтогаБылаВидна && экранИтога) экранИтога.classList.remove('экран--виден');
    нарисоватьОжидание();

    if (!хранилищеГотово()) {
      // Две причины на весь мир: хранилище не подключилось или память браузера
      // запрещена настройками. Обе лечатся одинаково — обновить страницу.
      нарисоватьПусто('Рекорды сейчас негде хранить: хранилище не подключилось. ' +
                      'Играть это не мешает, а рекорды появятся после обновления страницы.');
      return;
    }
    window.Рейтинг.прочитать(ИГРА).then(нарисовать).catch(function () {
      нарисоватьПусто('Рекорды не прочитались. Попробуйте открыть их ещё раз.');
    });
  }

  function спрятать() {
    if (экранРекордов) экранРекордов.classList.remove('экран--виден');
    if (экранДоски) экранДоски.classList.add('экран--виден');
    // Возвращаем плашку итога: партия-то по-прежнему окончена, и без плашки
    // человек увидел бы доску, которая не слушается, и никакой кнопки «ещё».
    if (плашкаИтогаБылаВидна && экранИтога) экранИтога.classList.add('экран--виден');
    плашкаИтогаБылаВидна = false;
  }

  /* Пока хранилище отвечает (в Telegram это до двух с половиной секунд),
     на экране должно быть хоть что-то: пустая страница читается как поломка. */
  function нарисоватьОжидание() {
    if (строкаЛучшего) строкаЛучшего.textContent = 'Читаем рекорды…';
    if (таблица) таблица.textContent = '';
  }

  function нарисоватьПусто(слова) {
    if (строкаЛучшего) строкаЛучшего.textContent = '';
    if (!таблица) return;
    таблица.textContent = '';
    var узел = document.createElement('p');
    узел.className = 'таблица__пусто';
    узел.textContent = слова;
    таблица.appendChild(узел);
  }

  function нарисовать(сводка) {
    if (!таблица) return;
    var всего = (сводка && сводка.всего) || null;
    if (!всего || всего.партий <= 0) {
      if (строкаЛучшего) строкаЛучшего.textContent = '';
      нарисоватьПусто('Рекордов пока нет. Сыграйте партию против робота — ' +
                      'победы подряд попадут сюда.');
      return;
    }

    if (строкаЛучшего) строкаЛучшего.textContent = словаОГлавном(сводка);
    таблица.textContent = '';
    таблица.appendChild(раздел('Серии побед по уровням'));
    for (var i = 0; i < УРОВНИ.length; i++) {
      таблица.appendChild(строкаПроУровень(сводка, УРОВНИ[i]));
    }
    таблица.appendChild(раздел('Последние партии'));
    нарисоватьПоследние(сводка);
  }

  /** Самая длинная серия из всех уровней — то, ради чего таблицу и открывают. */
  function словаОГлавном(сводка) {
    var лучшая = 0;
    var строки = сводка.поУровням || [];
    for (var i = 0; i < строки.length; i++) {
      if (строки[i].лучшаяСерия > лучшая) лучшая = строки[i].лучшаяСерия;
    }
    var всего = сводка.всего;
    var начало = лучшая > 0
      ? 'Лучшая серия: ' + лучшая + ' ' + словоПобед(лучшая) + ' подряд'
      : 'Побед подряд пока нет';
    return начало + ' · сыграно ' + всего.партий + ', побед ' + всего.побед;
  }

  /* Строка про один уровень.

     Подписи нарочно короткие: на телефоне в 320 точек в главную ячейку
     помещается около семнадцати знаков, а дальше строка обрезается
     многоточием — и обрезается как раз то, ради чего таблицу открыли.
     Так и вышло на первом снимке: «Лёгкий — 3 победы ...». Поэтому
     «Лёгкий: 3 подряд», а слово «победы» вынесено в заголовок раздела. */
  function строкаПроУровень(сводка, уровень) {
    var строка = строкаУровня(сводка, уровень);
    var имя = сБольшойБуквы(уровень);
    if (!строка || строка.партий <= 0) {
      return строкаТаблицы('', имя + ': не играли', '', '');
    }
    var главное = строка.лучшаяСерия > 0
      ? имя + ': ' + строка.лучшаяСерия + ' подряд'
      : имя + ': побед нет';
    var сейчас = строка.серияСейчас > 0 ? 'сейчас ' + строка.серияСейчас : '';
    return строкаТаблицы('', главное, сейчас, строка.партий + ' ' + словоПартий(строка.партий));
  }

  function нарисоватьПоследние(сводка) {
    var партии = (сводка.последниеПартии || []).slice(0, СКОЛЬКО_ПАРТИЙ_ПОКАЗЫВАЕМ);
    if (партии.length === 0) {
      var узел = document.createElement('p');
      узел.className = 'таблица__пусто';
      узел.textContent = 'Партий пока не записано.';
      таблица.appendChild(узел);
      return;
    }
    for (var i = 0; i < партии.length; i++) {
      var партия = партии[i];
      таблица.appendChild(строкаТаблицы(
        (i + 1) + '.',
        сБольшойБуквы(партия.исход || 'партия'),
        партия.дата || '',
        партия.уровень || ''
      ));
    }
  }

  /* Одна строка таблицы. Ячеек всегда четыре, даже когда какая-то пустая:
     раскладка строки в style.css рассчитана на четыре колонки, и строка
     из трёх ячеек уехала бы в чужие столбцы. */
  function строкаТаблицы(место, главное, слева, справа) {
    var узел = document.createElement('div');
    узел.className = 'таблица__строка';
    ячейка(узел, 'таблица__место', место);
    ячейка(узел, 'таблица__очки', главное);
    ячейка(узел, 'таблица__дата', слева);
    ячейка(узел, 'таблица__сложность', справа);
    return узел;
  }

  function ячейка(куда, класс, текст) {
    var узел = document.createElement('span');
    узел.className = класс;
    узел.textContent = текст;
    куда.appendChild(узел);
    return узел;
  }

  function раздел(слова) {
    var узел = document.createElement('div');
    узел.className = 'таблица__раздел';
    узел.textContent = слова;
    return узел;
  }

  /* Слово при числе: «1 победа», «2 победы», «5 побед». Считаем сами —
     это три строчки, а без них таблица говорит «3 побед» и выглядит
     недоделанной. Одиннадцать–четырнадцать вынесены отдельно: они
     кончаются на 1–4, а слово при них как при пяти. */
  function словоПобед(сколько) {
    return окончание(сколько, 'победа', 'победы', 'побед');
  }

  function словоПартий(сколько) {
    return окончание(сколько, 'партия', 'партии', 'партий');
  }

  function окончание(сколько, одна, две, много) {
    var десятки = сколько % 100;
    var единицы = сколько % 10;
    if (десятки >= 11 && десятки <= 14) return много;
    if (единицы === 1) return одна;
    if (единицы >= 2 && единицы <= 4) return две;
    return много;
  }

  function сБольшойБуквы(слова) {
    return слова ? слова[0].toUpperCase() + слова.slice(1) : '';
  }

  /* ------------------------------------------------------------------
     ПОДКЛЮЧЕНИЕ
     ------------------------------------------------------------------ */
  if (кнопкаНазад) кнопкаНазад.addEventListener('click', спрятать);

  window.ШашкиРекорды = {
    записатьПартию: записатьПартию,
    показать: показать,
    спрятать: спрятать,
    открыты: открыты
  };
})();
