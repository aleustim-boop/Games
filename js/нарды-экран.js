  /** Уйти на витрину — то же, что делает кнопка «Назад» в меню игры.
   *  Лобби теперь первый экран страницы, и шаг назад стал двухступенчатым,
   *  как у шашек и шахмат: со стола «Назад» ведёт в лобби, а уже
   *  с лобби — на витрину index.html. */
  function уйтиНаВитрину() {
    /* Со стола — шаг в лобби; из лобби — на витрину. И в том, и в другом
       случае человек уходит от стола, поэтому сетевую комнату покидаем. */
    покинутьСетьЕслиИдёт();
    if (экранЛобби && window.НардыЛоббиЗагружено && !экранЛобби.classList.contains('экран--виден')) {
      закрытьИтог();
      вМеню();
      return;
    }
    if (window.Телеграм && typeof window.Телеграм.спрятатьСтрелку === 'function') {
      window.Телеграм.спрятатьСтрелку();
    }
    window.location.href = 'index.html' + хвостСсылки();
  }

  /** Шаг назад с этого экрана — тот же, что у кнопки на нём. */
  function шагНазад(имя) {
    /* «экран-как-играть» и «экран-оформления» — экраны листа «⋯», где
       кнопка на самой странице возвращает не в меню, а туда, откуда
       пришли (стол или лобби) — см. «вернутьсяИзСлужебного» выше. */
    if (имя === 'экран-как-играть' || имя === 'экран-оформления') {
      вернутьсяИзСлужебного();
      return;
    }
    /* С самого лобби и с запасного экрана режимов (без лобби) —
       на витрину; уйтиНаВитрину сама решает, что из них сейчас видно. */
    if (имя === 'экран-лобби' || имя === 'экран-режимов') { уйтиНаВитрину(); return; }
    // Со стола, экрана бота, экрана друга и всех прочих — в меню игры.
    // Стрелка Telegram — один из путей ухода во время партии, поэтому
    // сперва спрашиваем общее подтверждение листа «⋯» (штаб/план-выход-
    // из-партии.md, Э5): «спроситьЗавершить» — на объекте, который вернул
    // ЛистЕщё.подключить(...) (переменная «листЕщё», см. «подключитьЛистЕщё»
    // ниже), тот же объект, где и «освежитьКнопкуНастроек». Вне партии или
    // без двери «завершить» он вернёт false, и уходим как раньше.
    if (листЕщё && листЕщё.спроситьЗавершить && листЕщё.спроситьЗавершить()) return;
    уйтиВМеню();
  }

  function освежитьСтрелкуНазад(имя) {
    const дверь = window.Телеграм;
    if (!дверь || typeof дверь.показатьСтрелку !== 'function') return;
    дверь.показатьСтрелку(function () { шагНазад(имя); });
  }

