    /* Панель сверху на доске всегда занимает тот же цвет, что и бот
       (см. ЦВЕТ_БОТА выше) — раскладка доски от режима не меняется,
       меняется только подпись: роль или цвет (см. подписиПанелей). */
    const подписи = подписиПанелей(режим, ЦВЕТ_БОТА, null);
