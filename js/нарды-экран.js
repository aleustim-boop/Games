  /* =====================================================================
     ЧАСТЬ 13. ВИД ДОСКИ

     12 сентября владелец решил убрать саму кнопку «Вид доски» со страницы
     нард (экран #экран-вида-доски и обе кнопки входа в нарды.html): доска
     сейчас одна — фотография из его набора, и три «вида» меняли лишь
     оттенок одной и той же картинки. Функции ниже нарочно оставлены
     нетронутыми, а не выкорчеваны: признак «data-доска» общий на весь
     сборник, его мог поставить выбор на странице шашек, и у игрока,
     который когда-то выбрал не «дерево», доска должна остаться прежней,
     а не сброситься. Кнопку и экран вернут, когда появятся настоящие
     разные доски (задача в очереди у штаба) — тогда в привязатьКнопки()
     («ЧАСТЬ 14») снова понадобится привязка кнопок вида доски.

     Выбор хранит общая дверь window.Оформление из js/telegram.js: она
     кладёт его в облако Telegram с откатом на память телефона, поэтому
     оформление едет за человеком на второе устройство. Она же САМА
     вешает признак «data-доска» на <html> — мы его не трогаем, иначе
     правда о том, какая доска стоит, оказалась бы в двух местах и
     однажды разошлась.

     ВАЖНАЯ ТОНКОСТЬ. При запуске вид ставится сразу из памяти телефона,
     чтобы не мигало, а из облака он может приехать чуть позже и
     оказаться новее. Значит, доска имеет право перекраситься через
     мгновение после открытия. Для доски это безвредно — цвет берётся из
     оформления, и ни один узел при этом не пересоздаётся, движение не
     ломается. А вот отметка «выбрано» на кнопке отстала бы, поэтому мы
     слушаем сам признак и переставляем её следом.
     ===================================================================== */

  const ВИДЫ_ДОСКИ = ['дерево', 'камень', 'классика'];

  /** Какая доска стоит сейчас. Спрашиваем у двери, а не у себя. */
  function какаяДоска() {
    try {
      if (window.Оформление && window.Оформление.какое) {
        const вид = window.Оформление.какое('доска');
        if (ВИДЫ_ДОСКИ.indexOf(вид) !== -1) return вид;
      }
    } catch (ошибка) { /* двери нет — обойдёмся видом по умолчанию */ }
    const наСтранице = document.documentElement.getAttribute('data-доска');
    return ВИДЫ_ДОСКИ.indexOf(наСтранице) === -1 ? 'дерево' : наСтранице;
  }

  function применитьДоску(имя) {
    const вид = ВИДЫ_ДОСКИ.indexOf(имя) === -1 ? 'дерево' : имя;
    try {
      if (window.Оформление && window.Оформление.поставить) window.Оформление.поставить('доска', вид);
      else document.documentElement.setAttribute('data-доска', вид);   // двери нет — хотя бы покажем
    } catch (ошибка) {
      document.documentElement.setAttribute('data-доска', вид);
    }
    отметитьВыбраннуюДоску();
  }

  /** Переставить отметку «выбрано» под то, что реально стоит на странице. */
  function отметитьВыбраннуюДоску() {
    const вид = какаяДоска();
    for (const название of ВИДЫ_ДОСКИ) {
      const кнопка = узел('доска-' + название);
      if (кнопка) кнопка.classList.toggle('кнопка--активная', название === вид);
    }
  }

  /**
   * Следим за признаком на <html>. Он меняется не только от нашей кнопки:
   * его же ставит дверь, когда из облака приезжает более свежий выбор —
   * в том числе сделанный на другом устройстве или на странице шашек.
   */
  function следитьЗаДоской() {
    if (typeof MutationObserver !== 'function') return;
    const сторож = new MutationObserver(отметитьВыбраннуюДоску);
    сторож.observe(document.documentElement, { attributes: true, attributeFilter: ['data-доска'] });
  }

