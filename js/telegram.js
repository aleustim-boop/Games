/* Связь игры с Telegram и хранение личных рекордов.

   Игра общается с этим файлом только тремя функциями:
     isReady()                — готово ли хранилище рекордов (обычное да/нет, сразу)
     saveScore(очки, сложность) — записать результат, возвращает обещание (Promise)
     loadScore()              — прочитать рекорды, возвращает обещание (Promise)

   Всё остальное — раскрытие окна на весь экран, цвета темы Telegram и выбор
   «облако или память браузера» — делается здесь и наружу не торчит.
   Вне Telegram файл работает точно так же: рекорды просто ложатся в память
   браузера (localStorage), и ни одной ошибки в консоли при этом нет. */

(function () {
  'use strict';

  // Ключ, под которым лежат рекорды и в облаке Telegram, и в памяти браузера
  var КЛЮЧ_РЕКОРДОВ = 'подкидной-дурак:рекорды';
  var МАКСИМУМ_ЗАПИСЕЙ = 10;                 // сколько строк держим в таблице рекордов
  var СЛОЖНОСТЬ_ПО_УМОЛЧАНИЮ = 'обычный';    // если игра не передала сложность
  var ДЛИНА_НОМЕРА_СЕРИИ = 40;               // длиннее номер быть не может — значит, это мусор
  // Сколько ждём ответа от облака Telegram. Не дождались — берём память браузера,
  // чтобы экран результата не завис в ожидании навсегда. Больше двух с половиной
  // секунд ждать нельзя: при сохранении подряд идут чтение и запись, а человек
  // всё это время смотрит на надпись «записываем» и решает, что игра сломалась.
  var ОЖИДАНИЕ_ОБЛАКА = 2500;
  // Облако не ответило — значит, связи сейчас нет. Полминуты к нему не ходим,
  // иначе каждая победа снова упирается в ожидание.
  var ПЕРЕРЫВ_ПОСЛЕ_ОСЕЧКИ = 30000;
  var облакоОтдыхаетДо = 0;

  // ---------------------------------------------------------------------------
  // Где мы находимся: есть ли Telegram и его облако
  // ---------------------------------------------------------------------------

  /** Объект Telegram WebApp, если игра открыта внутри Telegram. Иначе null. */
  function получитьWebApp() {
    try {
      if (window.Telegram && window.Telegram.WebApp) return window.Telegram.WebApp;
    } catch (ошибка) { /* нет так нет */ }
    return null;
  }

  // Облако появилось в Telegram начиная с этой версии
  var ВЕРСИЯ_С_ОБЛАКОМ = '6.9';

  /** Облачное хранилище Telegram, если оно доступно в этой версии приложения. Иначе null.
      Версию спрашиваем заранее: в обычном браузере скрипт Telegram делает вид, что облако
      есть, но на любое обращение ругается в консоль. Нам нужна чистая консоль. */
  function получитьОблако() {
    // Недавняя осечка: связи нет, лишний раз не ждём
    if (Date.now() < облакоОтдыхаетДо) return null;

    var приложение = получитьWebApp();
    if (!приложение || !приложение.CloudStorage) return null;

    try {
      if (typeof приложение.isVersionAtLeast === 'function' && !приложение.isVersionAtLeast(ВЕРСИЯ_С_ОБЛАКОМ)) {
        return null;
      }
    } catch (ошибка) {
      return null;
    }

    var облако = приложение.CloudStorage;
    if (typeof облако.getItem !== 'function' || typeof облако.setItem !== 'function') return null;
    return облако;
  }

  /** Проверяем память браузера один раз при загрузке: в некоторых режимах она запрещена. */
  function проверитьПамять() {
    try {
      var проба = '__проба-записи__';
      window.localStorage.setItem(проба, '1');
      window.localStorage.removeItem(проба);
      return true;
    } catch (ошибка) {
      return false;
    }
  }

  var памятьРаботает = проверитьПамять();

  // ---------------------------------------------------------------------------
  // Разбор и приведение данных в порядок
  // ---------------------------------------------------------------------------

  /** Пустой ответ: так выглядят рекорды у игрока, который ещё ничего не выиграл.
      «последняяСерия» — заметка о том, какую строку таблицы мы растили в прошлый раз;
      она лежит рядом с рекордами и потому переживает перезагрузку страницы. */
  function пустыеРекорды() {
    return { лучший: 0, таблица: [], последняяСерия: null };
  }

  /** Любое значение превращаем в неотрицательное целое число очков. */
  function целоеЧисло(значение) {
    var число = Number(значение);
    if (!isFinite(число) || число <= 0) return 0;
    return Math.floor(число);
  }

  /** Сегодняшняя дата в привычном виде 18.08.2026. Дату проставляем сами — игра её не передаёт. */
  function сегодняшняяДата() {
    var сейчас = new Date();
    var день = сейчас.getDate();
    var месяц = сейчас.getMonth() + 1;
    return (день < 10 ? '0' : '') + день + '.' + (месяц < 10 ? '0' : '') + месяц + '.' + сейчас.getFullYear();
  }

  /** Строка сложности: пустую или не-строку заменяем на «обычный». */
  function привестиСложность(значение) {
    if (typeof значение === 'string' && значение.trim()) return значение.trim();
    return СЛОЖНОСТЬ_ПО_УМОЛЧАНИЮ;
  }

  /** Номер серии из хранилища: годится только непустая строка, всё остальное — «номера нет».
      Длину ограничиваем, чтобы испорченный файл не раздул таблицу. */
  function привестиНомерСерии(значение) {
    if (typeof значение !== 'string') return '';
    var номер = значение.trim();
    if (!номер || номер.length > ДЛИНА_НОМЕРА_СЕРИИ) return '';
    return номер;
  }

  /**
   * Разбираем заметку о последней записанной серии.
   * У игроков, которые играли до появления этой заметки, в хранилище её просто нет —
   * тогда возвращаем null, и всё остальное читается как раньше. Мусор тоже даёт null.
   */
  function разобратьПамятьСерии(значение) {
    if (!значение || typeof значение !== 'object') return null;
    var очки = целоеЧисло(значение.очки);
    if (очки <= 0) return null;

    var заметка = {
      очки: очки,
      дата: typeof значение.дата === 'string' ? значение.дата : '',
      сложность: привестиСложность(значение.сложность),
      номерСерии: привестиНомерСерии(значение.номерСерии)
    };
    var прежние = разобратьПрежниеПриметы(значение.прежниеПриметы);
    if (прежние) заметка.прежниеПриметы = прежние;
    return заметка;
  }

  /**
   * Приметы, по которым строка этой же серии выглядела ДО того, как получила номер.
   * Нужны ровно на один случай: игрок обновил игру посреди серии. В другом хранилище
   * может лежать её прежний вид — строка без номера, и узнать её больше нечем.
   */
  function разобратьПрежниеПриметы(значение) {
    if (!значение || typeof значение !== 'object') return null;
    var очки = целоеЧисло(значение.очки);
    if (очки <= 0) return null;
    return {
      очки: очки,
      дата: typeof значение.дата === 'string' ? значение.дата : '',
      сложность: привестиСложность(значение.сложность)
    };
  }

  /** Превращаем сохранённый текст в объект рекордов. Мусор и поломанный текст не роняют игру. */
  function разобратьРекорды(текст) {
    if (!текст || typeof текст !== 'string') return пустыеРекорды();

    var данные;
    try {
      данные = JSON.parse(текст);
    } catch (ошибка) {
      return пустыеРекорды();
    }
    if (!данные || typeof данные !== 'object') return пустыеРекорды();

    var исходныйСписок = Array.isArray(данные.таблица) ? данные.таблица : [];
    var таблица = [];
    for (var i = 0; i < исходныйСписок.length && таблица.length < МАКСИМУМ_ЗАПИСЕЙ; i++) {
      var запись = исходныйСписок[i];
      if (!запись || typeof запись !== 'object') continue;
      var строка = {
        очки: целоеЧисло(запись.очки),
        дата: typeof запись.дата === 'string' ? запись.дата : '',
        сложность: привестиСложность(запись.сложность)
      };
      // Номер серии дописываем, только если он в записи есть. У строк, записанных
      // старой версией игры, его нет — и пусть не появляется: пустое поле в таблице
      // ни о чём не говорит, а место в хранилище занимает.
      var номер = привестиНомерСерии(запись.номерСерии);
      if (номер) строка.номерСерии = номер;
      таблица.push(строка);
    }

    var лучший = целоеЧисло(данные.лучший);
    for (var j = 0; j < таблица.length; j++) {
      if (таблица[j].очки > лучший) лучший = таблица[j].очки;
    }

    return {
      лучший: лучший,
      таблица: таблица,
      последняяСерия: разобратьПамятьСерии(данные.последняяСерия)
    };
  }

  // ---------------------------------------------------------------------------
  // Память браузера (запасной вариант)
  // ---------------------------------------------------------------------------

  function прочитатьИзПамяти() {
    if (!памятьРаботает) return '';
    try {
      return window.localStorage.getItem(КЛЮЧ_РЕКОРДОВ) || '';
    } catch (ошибка) {
      return '';
    }
  }

  function записатьВПамять(текст) {
    if (!памятьРаботает) return false;
    try {
      window.localStorage.setItem(КЛЮЧ_РЕКОРДОВ, текст);
      return true;
    } catch (ошибка) {
      return false;
    }
  }

  // ---------------------------------------------------------------------------
  // Облако Telegram (основной вариант)
  // ---------------------------------------------------------------------------

  /** Обёртка над облаком: любой сбой или молчание превращаются в отказ обещания. */
  function спроситьОблако(действие) {
    return new Promise(function (успех, отказ) {
      var облако = получитьОблако();
      if (!облако) {
        отказ(new Error('облака Telegram нет'));
        return;
      }

      var ответУжеБыл = false;
      var часы = setTimeout(function () {
        if (ответУжеБыл) return;
        ответУжеБыл = true;
        облакоОтдыхаетДо = Date.now() + ПЕРЕРЫВ_ПОСЛЕ_ОСЕЧКИ;
        отказ(new Error('облако не ответило вовремя'));
      }, ОЖИДАНИЕ_ОБЛАКА);

      function ответить(сбой, значение) {
        if (ответУжеБыл) return;
        ответУжеБыл = true;
        clearTimeout(часы);
        if (сбой) {
          облакоОтдыхаетДо = Date.now() + ПЕРЕРЫВ_ПОСЛЕ_ОСЕЧКИ;
          отказ(new Error(String(сбой)));
        } else {
          успех(значение);
        }
      }

      try {
        действие(облако, ответить);
      } catch (ошибка) {
        if (!ответУжеБыл) {
          ответУжеБыл = true;
          clearTimeout(часы);
          отказ(ошибка);
        }
      }
    });
  }

  function прочитатьИзОблака() {
    return спроситьОблако(function (облако, ответить) {
      облако.getItem(КЛЮЧ_РЕКОРДОВ, ответить);
    }).then(function (значение) {
      return typeof значение === 'string' ? значение : '';
    });
  }

  function записатьВОблако(текст) {
    return спроситьОблако(function (облако, ответить) {
      облако.setItem(КЛЮЧ_РЕКОРДОВ, текст, ответить);
    });
  }

  // ---------------------------------------------------------------------------
  // Чтение и запись рекордов: сначала облако, при любой осечке — память браузера
  // ---------------------------------------------------------------------------

  /**
   * Складываем два списка рекордов в один.
   * Это главное правило хранения: облако и память браузера не спорят, кто главнее,
   * а объединяются. Иначе победа, добытая без связи (она легла только в память
   * телефона), исчезала бы при первом же удачном ответе облака.
   * Одинаковой считаем запись, у которой совпали все три приметы: очки, дата
   * и уровень сложности. Уровень обязателен: «3 победы подряд на сложном» и
   * «3 победы подряд на лёгком» в один день — разные достижения, и второе даётся
   * труднее. Если сравнивать только по очкам и дате, вторая строка молча пропадёт.
   *
   * ОТДЕЛЬНО — ДВЕ СТРОКИ ОДНОЙ И ТОЙ ЖЕ СЕРИИ.
   * Облако может отстать от памяти телефона: запись туда сорвалась, и там осталась
   * та же серия, но короче — «1 подряд» против «3 подряд». По очкам они разные,
   * поэтому раньше склеить их было нечем, и обрывок оставался в таблице навсегда.
   * Теперь у каждой серии есть свой номер, и две строки с одним номером — заведомо
   * одна серия: оставляем ту, где побед больше, она и есть настоящая её длина.
   * У строк, записанных старой версией игры, номера нет — они складываются
   * по-прежнему, только по трём приметам, и ничего не теряют.
   */
  function сложитьРекорды(первые, вторые) {
    var всё = первые.таблица.concat(вторые.таблица);
    var видели = {};
    var местоСерии = {};      // номер серии → где её строка уже лежит в таблице
    var таблица = [];

    for (var i = 0; i < всё.length; i++) {
      var запись = всё[i];

      if (запись.номерСерии) {
        // Приставка нужна, чтобы номер из испорченного файла не притворился
        // служебным полем объекта (например, «__proto__»).
        var ключСерии = 'серия:' + запись.номерСерии;
        var местоРанее = местоСерии[ключСерии];
        if (typeof местоРанее === 'number') {
          // Та же серия, но одна из копий отстала — берём ту, где побед больше
          if (запись.очки > таблица[местоРанее].очки) таблица[местоРанее] = запись;
          continue;
        }
        местоСерии[ключСерии] = таблица.length;
        таблица.push(запись);
        continue;
      }

      var примета = запись.очки + '|' + запись.дата + '|' + запись.сложность;
      if (видели[примета] === true) continue;
      видели[примета] = true;
      таблица.push(запись);
    }

    var память = выбратьЗаметку(первые.последняяСерия, вторые.последняяСерия);
    // Чистим до обрезания десятки: иначе обрывок успеет вытеснить настоящий рекорд
    таблица = убратьПрежнийВидСтроки(таблица, память);

    таблица.sort(function (первая, вторая) { return вторая.очки - первая.очки; });
    таблица = таблица.slice(0, МАКСИМУМ_ЗАПИСЕЙ);

    var лучший = Math.max(целоеЧисло(первые.лучший), целоеЧисло(вторые.лучший));
    for (var j = 0; j < таблица.length; j++) {
      if (таблица[j].очки > лучший) лучший = таблица[j].очки;
    }

    return { лучший: лучший, таблица: таблица, последняяСерия: память };
  }

  /**
   * Какую из двух заметок о серии взять.
   * Обычно — ту, что с этого устройства (вторая, из памяти браузера): счёт побед
   * подряд игра тоже держит только здесь, на другом телефоне серия начинается заново.
   * Но если обе заметки об ОДНОЙ И ТОЙ ЖЕ серии (номер совпал), берём ту, где побед
   * больше. Это страховка на случай, когда память браузера отказала в записи,
   * а облако записалось: иначе устаревшая заметка сочтёт свою же серию чужой
   * и заведёт ей вторую строку.
   */
  function выбратьЗаметку(облачная, местная) {
    if (!местная) return облачная || null;
    if (!облачная) return местная;
    if (местная.номерСерии && местная.номерСерии === облачная.номерСерии) {
      return облачная.очки > местная.очки ? облачная : местная;
    }
    return местная;
  }

  /**
   * Выбрасываем строку, которая осталась от прежнего вида той же серии.
   *
   * Зачем. Игрок обновил игру посреди серии: в обоих хранилищах лежала строка
   * без номера («6 подряд»). Первая же победа вырастила местную строку до «7»
   * и впервые дала ей номер, а запись в облако сорвалась — там осталась «6 подряд»
   * без номера. По номеру их не свести (у одной его нет), по очкам они разные,
   * и брошенная «6» осталась бы в таблице навсегда, заняв место в десятке.
   *
   * Выбрасываем строго осторожно: только ту строку, чьи приметы мы сами записали
   * в заметку как прежний вид ЭТОЙ серии, и только если рядом уже лежит её нынешняя
   * строка с номером. Просто «похожие дата и уровень» не годятся: две честные серии,
   * разорванные проигрышем в один день на одном уровне, так склеились бы в одну
   * и живой рекорд бы пропал.
   */
  function убратьПрежнийВидСтроки(таблица, заметка) {
    if (!заметка || !заметка.номерСерии || !заметка.прежниеПриметы) return таблица;
    var прежние = заметка.прежниеПриметы;

    var естьНынешняя = false;
    for (var i = 0; i < таблица.length; i++) {
      if (таблица[i].номерСерии === заметка.номерСерии) { естьНынешняя = true; break; }
    }
    if (!естьНынешняя) return таблица;

    var очищенная = [];
    for (var j = 0; j < таблица.length; j++) {
      var строка = таблица[j];
      var этоПрежнийВид = !строка.номерСерии &&
        строка.очки === прежние.очки &&
        строка.дата === прежние.дата &&
        строка.сложность === прежние.сложность;
      if (!этоПрежнийВид) очищенная.push(строка);
    }
    return очищенная;
  }

  function прочитатьРекорды() {
    // Местные рекорды читаем всегда: в них лежат победы, добытые без связи
    var местные = разобратьРекорды(прочитатьИзПамяти());

    return прочитатьИзОблака()
      .then(function (текст) {
        // Облачные ставим первыми: при равных очках они и останутся выше
        return сложитьРекорды(разобратьРекорды(текст), местные);
      })
      .catch(function () {
        // Облака нет, оно молчит или отказало — работаем с памятью браузера
        return местные;
      });
  }

  function записатьРекорды(рекорды) {
    var текст = JSON.stringify(рекорды);
    // В память браузера пишем всегда: если облако промолчит, рекорд всё равно уцелеет.
    записатьВПамять(текст);
    return записатьВОблако(текст).catch(function () {
      // Облака нет или оно отказало — это нормально, в памяти браузера уже сохранено.
      return null;
    });
  }

  // ---------------------------------------------------------------------------
  // Серия побед подряд занимает одну строку, а не десять ступенек
  // ---------------------------------------------------------------------------

  // Игра сообщает результат после каждой победы: 1, 2, 3… Если записывать каждый
  // раз новую строку, серия из десяти побед займёт всю таблицу («10 подряд»,
  // «9 подряд», «8»…), хотя результат по сути один. Поэтому помним последнюю
  // записанную серию и растим её строку.
  //
  // Заметку о ней держим НЕ в переменной страницы, а в самом хранилище рядом
  // с таблицей. Иначе выходила беда: игра длину серии помнит (она лежит в памяти
  // браузера), а рекорды после перезагрузки — уже нет, и заводят новую строку.
  // В Telegram страница запускается заново при каждом открытии из бота, так что
  // ступеньки получались почти у каждого игрока.

  /**
   * Придумать номер новой серии — примету, по которой её строку потом узнают.
   *
   * Из чего собран и почему не повторится:
   *   — время начала серии (миллисекунды, записанные покороче) — две серии на одном
   *     устройстве не начинаются в одну и ту же миллисекунду;
   *   — две случайные добавки — они разводят устройства одного и того же игрока.
   * Вторая часть здесь важнее краткости: телефон и планшет, подключённые к одному
   * облаку, часы имеют почти одинаковые. Совпади номера у РАЗНЫХ серий — их бы
   * склеило в одну и один рекорд пропал бы, а это хуже, чем длинная строка в файле.
   */
  function новыйНомерСерии() {
    // Нули в хвосте не для красоты: у «круглого» случайного числа запись короткая
    // (0.5 — это «0.i»), и без них добавка иногда выходила короче шести знаков.
    var случайная = function () {
      return (Math.random().toString(36) + '0000000').slice(2, 8);
    };
    return Date.now().toString(36) + '-' + случайная() + случайная();
  }

  // Уровни соперника от самого лёгкого к самому трудному — так их называет игра.
  //
  // ЭТОТ СПИСОК ОБЯЗАН СЛОВО В СЛОВО СОВПАДАТЬ со списком «СЛОЖНОСТИ» в js/game.js —
  // вплоть до буквы «ё» в «лёгкий». Этими словами игра называет уровень соперника,
  // и по ним мы решаем, какой уровень легче.
  // Вторым доводом saveScore приходит не одно такое слово, а ПОДПИСЬ: за столом
  // компанией игра дописывает к уровню стол — «сложный · вчетвером». Уровень в ней
  // стоит первым, до разделителя, и достаётся отсюда (см. «уровеньИзПодписи» ниже).
  // Если списки разойдутся (уровень переименуют там и забудут здесь), ничего не сломается
  // заметно и в консоли не будет ни одной ошибки: незнакомое слово просто не пойдёт в счёт,
  // и подписи серий начнут молча врать — покажут не самый лёгкий уровень, а какой попало.
  // Переименовали уровень в игре — переименуйте и здесь.
  var ПОРЯДОК_УРОВНЕЙ = ['лёгкий', 'обычный', 'сложный'];

  /* Подпись, которую присылает игра, бывает СОСТАВНОЙ: «сложный · вчетвером».
     Уровень в ней стоит первым, до разделителя, а дальше — за каким столом
     набрана серия.

     Откуда это взялось. Победы за столом компанией теперь тоже идут в рекорды,
     а выигрывать компанией заметно легче (по замеру вшестером человек берёт
     149 партий из 200, один на один — 67). В таблице обе выглядели одинаково,
     поэтому игра стала дописывать стол к уровню. Игра один на один подписана
     по-прежнему одним словом — «сложный», без добавки.

     Почему без этого разбора подписи молча врут — ровно то, о чём предупреждает
     заметка выше: «сложный · вчетвером» в списке уровней не находится, счёт
     самого лёгкого ломается, и серия, начатая на лёгком сопернике, получает
     подпись «сложный». Это приписка заслуги, от которой мы и защищаемся. */
  var РАЗДЕЛИТЕЛЬ_ПОДПИСИ = ' · ';

  /** Уровень из подписи: то, что стоит до разделителя (или вся подпись). */
  function уровеньИзПодписи(подпись) {
    var строка = String(подпись);
    var место = строка.indexOf(РАЗДЕЛИТЕЛЬ_ПОДПИСИ);
    return место < 0 ? строка : строка.slice(0, место);
  }

  /** Хвост подписи: за каким столом. Пусто — значит игра была один на один. */
  function столИзПодписи(подпись) {
    var строка = String(подпись);
    var место = строка.indexOf(РАЗДЕЛИТЕЛЬ_ПОДПИСИ);
    return место < 0 ? '' : строка.slice(место + РАЗДЕЛИТЕЛЬ_ПОДПИСИ.length);
  }

  /**
   * Чем подписать серию, сыгранную двумя подписями подряд.
   *
   * Имя нарочно про подпись, а не про уровень: возвращается целая подпись,
   * вместе со столом. Прежнее имя обещало одно слово и сбивало читателя с толку.
   *
   * Уровень берём САМЫЙ ЛЁГКИЙ из двух: незнакомое слово в счёт не идёт,
   * берём тот уровень, который мы знаем.
   * Стол берём у ПОСЛЕДНЕЙ партии (второй довод) — так решено в игре:
   * обрывать серию из-за смены стола нечестно, а пометить её составом
   * последней партии честнее, чем не пометить вовсе.
   */
  function подписьПродолженнойСерии(первый, второй) {
    var уровеньПервого = уровеньИзПодписи(первый);
    var уровеньВторого = уровеньИзПодписи(второй);
    var местоПервого = ПОРЯДОК_УРОВНЕЙ.indexOf(уровеньПервого);
    var местоВторого = ПОРЯДОК_УРОВНЕЙ.indexOf(уровеньВторого);
    var лёгкий;
    if (местоПервого < 0) лёгкий = уровеньВторого;
    else if (местоВторого < 0) лёгкий = уровеньПервого;
    else лёгкий = местоПервого <= местоВторого ? уровеньПервого : уровеньВторого;
    var стол = столИзПодписи(второй);
    return стол ? лёгкий + РАЗДЕЛИТЕЛЬ_ПОДПИСИ + стол : лёгкий;
  }

  /**
   * Та же ли это серия, что мы записывали в прошлый раз.
   * Продолжением считаем результат ровно на одну победу больше предыдущего.
   * Уровень при этом может смениться: игра из-за смены соперника серию не
   * обрывает, значит, и таблица не должна разбивать её на две строки.
   * Новая серия всегда начинается с меньшего числа, поэтому чужие рекорды
   * такое правило не затрагивает.
   *
   * Вопрос «та же ли серия» намеренно отделён от вопроса «есть ли ещё её строка
   * в таблице». У игрока с богатой историей короткие серии в десятку не влезают
   * и вылетают, но серия при этом продолжается — и подписать её надо всё равно
   * по заметке, а не по сегодняшнему сопернику.
   */
  function серияПродолжается(рекорды, результат) {
    var память = рекорды.последняяСерия;
    if (!память) return false;
    return результат === память.очки + 1;
  }

  /**
   * Ищем в таблице строку той серии, о которой говорит заметка.
   * Сначала по номеру — это самая надёжная примета. Не нашли (номера в заметке нет
   * или он пропал из строки, например запись в хранилище испортилась) — ищем
   * по-старому, по трём приметам: так файл работал до появления номеров, и хуже
   * от запасного хода не станет. Без него та же серия завела бы себе вторую строку,
   * и игрок увидел бы сразу «3 подряд» и «4 подряд».
   * Нашли — вернём саму строку, нет — null (строка выпала из десятки, нужна новая).
   */
  function найтиСтрокуСерии(рекорды) {
    var память = рекорды.последняяСерия;
    if (!память) return null;
    var i, строка;

    if (память.номерСерии) {
      for (i = 0; i < рекорды.таблица.length; i++) {
        строка = рекорды.таблица[i];
        if (строка.номерСерии === память.номерСерии) return строка;
      }
    }

    for (i = 0; i < рекорды.таблица.length; i++) {
      строка = рекорды.таблица[i];
      // Строка с чужим номером — заведомо другая серия, её приметы ни о чём не говорят
      if (строка.номерСерии && строка.номерСерии !== память.номерСерии) continue;
      if (строка.очки === память.очки &&
          строка.дата === память.дата &&
          строка.сложность === память.сложность) {
        return строка;
      }
    }
    return null;
  }

  /**
   * Номер продолжающейся серии.
   * Обычно он лежит в заметке. Если заметка досталась от прежней версии игры,
   * номера в ней нет — тогда придумываем его прямо сейчас: серия та же, просто
   * до этой минуты её нечем было пометить.
   */
  function номерПродолжаемойСерии(рекорды) {
    var память = рекорды.последняяСерия;
    if (память && память.номерСерии) return память.номерСерии;
    return новыйНомерСерии();
  }

  /**
   * Чем подписать строку серии: уровнем, а за столом компанией — уровнем и столом.
   * Уровень берём САМЫЙ ЛЁГКИЙ из сыгранных в этой серии, а не последний. Рекорд не должен
   * приписывать игроку заслугу, которой не было: если серию начали на лёгком сопернике,
   * а доиграли на сложном — это не «серия на сложном», и подписывать её так нечестно.
   */
  function уровеньСтрокиСерии(рекорды, режим) {
    if (!рекорды.последняяСерия) return режим;
    return подписьПродолженнойСерии(рекорды.последняяСерия.сложность, режим);
  }

  /** Кладём заметку о серии рядом с таблицей — чтобы она пережила перезагрузку.
      Имя нарочно длинное: в js/game.js есть своя «запомнитьСерию», и она про другое —
      пишет длину серии в память браузера. Похожие имена легко перепутать. */
  function запомнитьЗаметкуОСерии(рекорды, результат, дата, режим, номер, прежние) {
    var заметка = {
      очки: результат, дата: дата, сложность: режим, номерСерии: номер
    };
    if (прежние) заметка.прежниеПриметы = прежние;
    рекорды.последняяСерия = заметка;
  }

  /**
   * Как выглядела строка серии до того, как получила номер.
   * Пока серия идёт, эту примету не теряем: копия старого вида может лежать
   * в другом хранилище и всплыть позже — например, когда вернётся связь.
   * Серия оборвалась — заметка заводится заново, и примета уходит вместе с ней.
   */
  function прежнийВидСтроки(рекорды, продолжаем, строкаСерии) {
    if (строкаСерии && !строкаСерии.номерСерии) {
      // Первый рост строки, доставшейся от прежней версии игры: снимаем её приметы,
      // потому что сейчас мы их перепишем и узнать старую копию будет больше нечем.
      return {
        очки: строкаСерии.очки,
        дата: строкаСерии.дата,
        сложность: строкаСерии.сложность
      };
    }
    if (продолжаем && рекорды.последняяСерия && рекорды.последняяСерия.прежниеПриметы) {
      return рекорды.последняяСерия.прежниеПриметы;
    }
    return null;
  }

  // ---------------------------------------------------------------------------
  // Три функции, которыми пользуется игра
  // ---------------------------------------------------------------------------

  /**
   * Ответ для игры: ровно то, что обещано в договоре, —
   * { лучший, таблица: [ { очки, дата, сложность } ] }.
   * Служебное наружу не отдаём: ни заметку о последней серии, ни номера серий
   * в строках. Это наша внутренняя кухня хранения, игре она не нужна и в договоре
   * её нет. Поэтому строки пересобираем по одному полю, а не отдаём как есть.
   */
  function ответДляИгры(рекорды) {
    var таблица = [];
    for (var i = 0; i < рекорды.таблица.length; i++) {
      var строка = рекорды.таблица[i];
      таблица.push({ очки: строка.очки, дата: строка.дата, сложность: строка.сложность });
    }
    return { лучший: рекорды.лучший, таблица: таблица };
  }

  /** Готово ли хранилище рекордов к работе. Обычное да/нет, без обещаний. */
  function isReady() {
    return памятьРаботает || получитьОблако() !== null;
  }

  /**
   * Записать результат партии.
   * очки — длина серии побед подряд (число).
   * сложность — необязательная строка; не передали — считаем «обычный».
   * Дату проставляем здесь сами. Обещание никогда не «падает»: даже если сохранить
   * не удалось, игра получит объект рекордов и спокойно покажет экран результата.
   */
  function saveScore(очки, сложность) {
    var результат = целоеЧисло(очки);
    var режим = привестиСложность(сложность);

    return прочитатьРекорды()
      .then(function (рекорды) {
        var дата = сегодняшняяДата();
        // Продолжение серии определяем по заметке, а не по наличию строки в таблице:
        // строка могла вылететь из десятки, но серия от этого не оборвалась.
        var продолжаем = серияПродолжается(рекорды, результат);
        var уровень = продолжаем ? уровеньСтрокиСерии(рекорды, режим) : режим;
        // Новая серия получает свой номер, продолжение — оставляет прежний
        var номер = продолжаем ? номерПродолжаемойСерии(рекорды) : новыйНомерСерии();
        var строкаСерии = продолжаем ? найтиСтрокуСерии(рекорды) : null;
        // Снимаем приметы ДО того, как перепишем строку: потом узнать её будет нечем
        var прежние = прежнийВидСтроки(рекорды, продолжаем, строкаСерии);

        if (строкаСерии) {
          // Та же серия стала длиннее — растим её строку, новую не заводим
          строкаСерии.очки = результат;
          строкаСерии.дата = дата;
          строкаСерии.сложность = уровень;
          строкаСерии.номерСерии = номер;
        } else {
          рекорды.таблица.push({
            очки: результат, дата: дата, сложность: уровень, номерСерии: номер
          });
        }
        запомнитьЗаметкуОСерии(рекорды, результат, дата, уровень, номер, прежние);

        // Лучшие сверху. При равных очках выше остаётся тот, кто добился раньше:
        // сортировка в браузере устойчивая и порядок одинаковых записей не меняет.
        рекорды.таблица.sort(function (первая, вторая) { return вторая.очки - первая.очки; });
        рекорды.таблица = рекорды.таблица.slice(0, МАКСИМУМ_ЗАПИСЕЙ);
        if (результат > рекорды.лучший) рекорды.лучший = результат;

        return записатьРекорды(рекорды).then(function () { return ответДляИгры(рекорды); });
      })
      .catch(function () {
        return ответДляИгры(пустыеРекорды());
      });
  }

  /**
   * Прочитать рекорды.
   * Обещание всегда приходит с объектом { лучший: число, таблица: [ { очки, дата, сложность } ] },
   * до 10 записей, лучшие сверху. Рекордов нет — { лучший: 0, таблица: [] }.
   */
  function loadScore() {
    return прочитатьРекорды()
      .then(ответДляИгры)
      .catch(function () { return ответДляИгры(пустыеРекорды()); });
  }

  // ---------------------------------------------------------------------------
  // Подключение к Telegram: раскрыть окно и взять цвета темы
  // ---------------------------------------------------------------------------

  // Слева — как поле называется у Telegram, справа — переменная CSS для дизайнера
  var ЦВЕТА_ТЕМЫ = [
    ['bg_color', '--tg-theme-bg-color'],
    ['text_color', '--tg-theme-text-color'],
    ['hint_color', '--tg-theme-hint-color'],
    ['button_color', '--tg-theme-button-color'],
    ['button_text_color', '--tg-theme-button-text-color'],
    ['secondary_bg_color', '--tg-theme-secondary-bg-color']
  ];

  /**
   * Переносим цвета темы Telegram в переменные CSS — но только все шесть разом.
   *
   * ПОЧЕМУ НЕЛЬЗЯ СТАВИТЬ ЦВЕТА ПО ОДНОМУ (не «упрощайте» обратно):
   * Telegram присылает набор цветов не всегда целиком. Стоит взять из него один
   * цвет, а остальные оставить наши — получается смесь двух палитр, которую никто
   * не проверял. Живой пример: пришёл белый цвет текста кнопки, а цвет самой кнопки
   * не пришёл и остался наш янтарный — белые буквы на янтарном фоне читать
   * невозможно. Так сломались и строка подсказки, и главные кнопки.
   * Поэтому правило простое: пришли все шесть — берём тему Telegram; пришло
   * меньше — не берём ничего и оставляем свою палитру из style.css целиком,
   * она согласована сама с собой и проверена на читаемость.
   */
  function применитьТему() {
    var приложение = получитьWebApp();
    if (!приложение || !document.documentElement) return;

    var тема = приложение.themeParams || {};
    var корень = document.documentElement;

    // Сначала убеждаемся, что пришли ВСЕ цвета, и только потом что-то меняем
    for (var i = 0; i < ЦВЕТА_ТЕМЫ.length; i++) {
      var цвет = тема[ЦВЕТА_ТЕМЫ[i][0]];
      if (typeof цвет !== 'string' || !цвет) {
        забытьТемуTelegram(корень);
        return;
      }
    }

    for (var j = 0; j < ЦВЕТА_ТЕМЫ.length; j++) {
      корень.style.setProperty(ЦВЕТА_ТЕМЫ[j][1], тема[ЦВЕТА_ТЕМЫ[j][0]]);
    }
  }

  /** Снимаем ранее выставленные цвета Telegram: игра возвращается к своей палитре.
      Нужно на случай, когда полная тема сменилась неполной — чтобы не осталось
      половины старых цветов вперемешку с нашими. */
  function забытьТемуTelegram(корень) {
    for (var i = 0; i < ЦВЕТА_ТЕМЫ.length; i++) {
      корень.style.removeProperty(ЦВЕТА_ТЕМЫ[i][1]);
    }
  }

  var ужеПодключились = false;

  /** Один раз здороваемся с Telegram: говорим «готово», раскрываем окно, берём тему. */
  function подключитьсяКTelegram() {
    if (ужеПодключились) return true;
    var приложение = получитьWebApp();
    if (!приложение) return false;
    ужеПодключились = true;

    try { if (typeof приложение.ready === 'function') приложение.ready(); } catch (ошибка) { /* не страшно */ }
    // expand — чтобы игра открылась во весь экран, а не висела шторкой снизу
    try { if (typeof приложение.expand === 'function') приложение.expand(); } catch (ошибка) { /* не страшно */ }

    применитьТему();
    // Игрок может переключить светлую/тёмную тему прямо во время игры
    try {
      if (typeof приложение.onEvent === 'function') приложение.onEvent('themeChanged', применитьТему);
    } catch (ошибка) { /* не страшно */ }

    return true;
  }

  if (!подключитьсяКTelegram()) {
    // Скрипт Telegram мог ещё не догрузиться — пробуем ещё раз, когда страница будет готова
    window.addEventListener('load', function () { подключитьсяКTelegram(); });
  }

  // Наружу отдаём ровно три функции — это весь договор с игрой
  window.isReady = isReady;
  window.saveScore = saveScore;
  window.loadScore = loadScore;
})();
