'use strict';
// Знаки внимания «Захвата»: свой набор фраз (ТЗ, раздел 6), эмоции и броски — те же, что у
// js/деберц-знаки.js. Вид файла тот же, чтобы комната (server/комнаты.js) читала его так же.
// Номера идут подряд: сначала эмоции, потом фразы, потом броски. Менять порядок и вставлять
// в середину нельзя — номера живут в журналах партий; новое — только в конец своего списка.
(function () {
const ЭМОЦИИ = ['🙂', '😄', '😮', '😢', '👍', '🎉', '😎', '🤔', '😅', '🙏', '👏', '🔥'];
const ФРАЗЫ = [
  'Мир?',               // предложить не бить друг друга
  'Союз?',              // позвать в союз на словах (формальных союзов в игре нет)
  'Согласен',           // ответ на «Мир?» и «Союз?»
  'Нет',                // вежливый отказ
  'Бьём лидера!',       // позвать остальных против того, кто вырвался вперёд
  'Предатель!',         // про нарушенное слово
  'Помогите!',          // попросить поддержки
  'Хорошая игра'        // чем партию заканчивают
];
const БРОСКИ = [
  { ключ: 'какашка', имя: 'Какашка', винительный: 'какашку', злой: true },
  { ключ: 'помидор', имя: 'Помидор', винительный: 'помидор', злой: true },
  { ключ: 'яйцо', имя: 'Яйцо', винительный: 'яйцо', злой: true },
  { ключ: 'тапок', имя: 'Тапок', винительный: 'тапок', злой: true },
  { ключ: 'сердце', имя: 'Сердце', винительный: 'сердце', злой: false },
  { ключ: 'роза', имя: 'Роза', винительный: 'розу', злой: false },
  { ключ: 'торт', имя: 'Торт', винительный: 'торт', злой: false },
  { ключ: 'огонь', имя: 'Огонь', винительный: 'огонь', злой: false },
  { ключ: 'шарик-с-водой', имя: 'Шарик с водой', винительный: 'шарик с водой', злой: true },
  { ключ: 'банан', имя: 'Банан', винительный: 'банан', злой: true },
  { ключ: 'рыба', имя: 'Рыба', винительный: 'рыбу', злой: true },
  { ключ: 'снежок', имя: 'Снежок', винительный: 'снежок', злой: true },
  { ключ: 'перчатка', имя: 'Перчатка', винительный: 'перчатку', злой: true },
  { ключ: 'бомба', имя: 'Бомба', винительный: 'бомбу', злой: true },
  { ключ: 'пиво', имя: 'Пиво', винительный: 'пиво', злой: false }
];
const список = [...ЭМОЦИИ, ...ФРАЗЫ, ...БРОСКИ.map(x => x.имя)];
const этоЗнак = n => Number.isInteger(n) && n >= 0 && n < список.length;
const этоБросок = n => этоЗнак(n) && n >= ЭМОЦИИ.length + ФРАЗЫ.length;
const предмет = n => этоБросок(n) ? БРОСКИ[n - ЭМОЦИИ.length - ФРАЗЫ.length] : null;
// Фразы, которые говорят одному игроку (ТЗ, раздел 6): их видят только адресат и сказавший.
const ФРАЗЫ_ОДНОМУ = ['Мир?', 'Союз?', 'Согласен', 'Нет', 'Предатель!'];
/* Нужен ли знаку адресат. По этому ответу общая панель (js/деберц-сказать.js)
   спрашивает «кому сказать», а комната (server/комнаты.js) без адресата знак
   не принимает. Бросок без адресата не бывает — у него тоже true. */
const нужнаЦель = n => этоБросок(n) || (этоЗнак(n) && ФРАЗЫ_ОДНОМУ.indexOf(список[n]) !== -1);
const З = { ЭМОЦИИ, ФРАЗЫ, БРОСКИ, этоЗнак, этоБросок, нужнаЦель, предмет, текст: n => список[n] || '', сколько: () => список.length };
if (typeof module !== 'undefined') module.exports = З;
if (typeof window !== 'undefined') window.ЗахватЗнаки = З;
})();
