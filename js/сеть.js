  /**
   * Выйти из партии: сказать серверу (чтобы друг сразу увидел уход),
   * погасить опрос и забыть ключи. Вызывать можно всегда — если сетевой
   * партии нет, ничего не произойдёт.
   */
  function покинутьПартию() {
    остановитьОпрос();
    остановитьЧасовогоСвязи();
    остановитьЧасовогоВладения();
    новоеПоколение();       // всё, что ещё летит, к этой партии уже не относится
    показатьСвязь('');
    вПартии = false;
    последнееСостояние = null;
    приветствиеДо = 0;
    /* Кнопка пересбора живёт на общем экране итога — том же, что и в игре
       с ботом. Уходя из комнаты, прячем её сами: состояний от сервера
       больше не придёт, и спрятать её будет уже некому. */
    обновитьКнопкуПересбора(null);
    if (!код || !пропуск) return;
    const уходящийКод = код;
    const уходящийПропуск = пропуск;
    код = null;
    пропуск = null;
    забытьКомнату();
    // Ответ нам уже не нужен: мы уходим в любом случае.
    запрос('/выйти', { код: уходящийКод, пропуск: уходящийПропуск });
  }

