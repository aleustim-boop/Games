/* =====================================================================
   Игра вдвоём: разговор с сервером.

   Этот файл — единственное место, которое знает про сеть. Правил игры
   здесь нет вовсе: их считает сервер, а мы только отправляем намерения
   («хочу сходить этой картой») и показываем то, что он ответил.

   Как всё устроено:
     1. Человек создаёт игру — сервер выдаёт код из четырёх знаков
        и пропуск. Код диктуют другу, пропуск храним у себя.
     2. Друг входит по коду, партия начинается.
     3. Дальше работает «длинный опрос»: мы спрашиваем сервер
        «что нового?», он придерживает ответ, пока за столом что-нибудь
        не произойдёт, и отвечает новым состоянием. Ответил — спрашиваем
        снова, и так всю партию.

   Почему пропуск важнее кода: код перестаёт работать, как только
   в комнату вошли двое. Вернуться в свою партию после обрыва связи
   можно только по пропуску, поэтому он лежит в памяти браузера.

   Где проходит граница с js/game.js. Стол с картами этот файл не рисует
   совсем: готовое состояние уходит в js/game.js через мост ИграПоСети —
   там его превращают в карты, подсказки и кнопки. Зато служебные экраны
   сетевого режима — «Игра с другом», плашка с кодом, вход по коду, — со
   всеми их надписями и сообщениями пишет прямо этот файл: в одиночной
   игре таких экранов нет, и js/game.js про них ничего не знает. Само
   переключение между экранами и строку связи над столом файл тоже просит
   у js/game.js через мост, а не трогает своими руками.
   ===================================================================== */

'use strict';

(function () {

  /* -------------------------------------------------------------------
     Адрес сервера
     ------------------------------------------------------------------- */

  /* Главный способ задать адрес — в самом адресе страницы:
       index.html?сервер=https://адрес-сервера
     Так его можно поменять в настройках бота (GAME_URL), не трогая код
     и не поднимая номер версии файла. Константа ниже — только запасной
     вариант для игры на своём компьютере.
     В памяти браузера адрес нарочно не храним: устаревший адрес,
     всплывший через месяц, ищется дольше, чем отсутствующий. */
  const АДРЕС_ПО_УМОЛЧАНИЮ = 'http://127.0.0.1:8765';

  const ОБЫЧНОЕ_ОЖИДАНИЕ = 10 * 1000;      // сколько ждём короткий ответ
  const ОЖИДАНИЕ_ОПРОСА = 40 * 1000;       // длинный опрос сервер держит 25 секунд
  const ПАУЗА_ПОСЛЕ_СБОЯ = 1000;           // первая пауза перед повтором
  const МАКСИМАЛЬНАЯ_ПАУЗА = 10 * 1000;    // дальше паузы не растут
  const ДОЛГОЕ_РАЗДУМЬЕ = 10 * 1000;       // после этого пишем «друг думает»
  const ПОКАЗ_ПРИВЕТСТВИЯ = 4000;          // сколько висит «друг пришёл»
  const ЧАСТОТА_СТРОКИ_СВЯЗИ = 1000;       // как часто освежаем надпись о связи
  /* Сервер отвечает на длинный опрос не позже чем через 25 секунд, даже
     когда новостей нет. Значит, молчание дольше этого — уже не тишина
     за столом, а оборванная связь, и человеку пора об этом сказать.
     Десять секунд сверху — запас на медленную сеть, чтобы не пугать
     человека тревогой на ровном месте. */
  const МОЛЧАНИЕ_ЭТО_ОБРЫВ = 35 * 1000;

  /* Где лежит ключ от своей партии. Пропуск — это не пароль от чего-то
     ценного: он открывает одну комнату с картами и живёт минуты. */
  const КЛЮЧ_КОМНАТЫ = 'подкидной-дурак:комната';

  /** Адрес сервера: сначала из адреса страницы, потом — запасной. */
  function адресСервера() {
    let изАдреса = '';
    try {
      const разбор = new URLSearchParams(window.location.search);
      // Русское название удобно человеку, латинское — тому, кто правит
      // настройки бота в консоли. Принимаем оба.
      изАдреса = разбор.get('сервер') || разбор.get('server') || '';
    } catch (сбой) {
      изАдреса = '';
    }
    const адрес = (изАдреса || АДРЕС_ПО_УМОЛЧАНИЮ).trim();
    return адрес.replace(/\/+$/, '');   // хвостовой знак «/» только мешает
  }

  /**
   * Почему по этому адресу играть не выйдет. Проверяем до первой попытки:
   * иначе браузер скажет невнятное «не удалось подключиться», и человек
   * будет искать причину весь вечер.
   */
  function почемуАдресНеПодходит(адрес) {
    if (!/^https?:\/\//i.test(адрес)) {
      return 'Адрес сервера должен начинаться с http:// или https://, а сейчас это «' +
             адрес + '». Исправьте адрес игры.';
    }
    // Защищённая страница (а в Telegram она всегда защищённая) не имеет права
    // обращаться к незащищённому адресу — браузер запрещает это молча.
    if (window.location.protocol === 'https:' && /^http:\/\//i.test(адрес)) {
      return 'Игра открыта по защищённому адресу (https), а сервер игры вдвоём — ' +
             'по обычному (http). Браузер такие запросы запрещает, и партия ' +
             'не начнётся. Нужен сервер по адресу https:// — либо откройте игру ' +
             'с обычного http-адреса на своём компьютере.';
    }
    return null;
  }

  /* -------------------------------------------------------------------
     Память о своей комнате
     ------------------------------------------------------------------- */

  /* Своё имя этой открытой страницы. Память браузера одна на все вкладки,
     поэтому в записи о комнате отмечено, какая вкладка сейчас за столом:
     иначе вторая вкладка садится на то же место, а её выход выкидывает
     из партии и первую — друг видит «Друг вышел», хотя человек играет. */
  const КЛЮЧ_ИМЕНИ_ВКЛАДКИ = 'подкидной-дурак:вкладка';

  function придуматьИмя() {
    return Math.random().toString(36).slice(2) + Date.now().toString(36);
  }

  /**
   * Имя берём из памяти самой вкладки (sessionStorage). Она у каждой вкладки
   * своя и переживает перезагрузку страницы — а это ровно то, что нужно:
   * после обновления вкладка узнаёт собственную запись о комнате и зовёт
   * вернуться в игру. Со случайным именем при каждой загрузке она принимала
   * себя же за соседнюю вкладку и первые пятнадцать секунд отказывалась
   * возвращаться в свою партию.
   * Вкладка, открытая обычным способом, чужой памяти не наследует, имя
   * получает другое, поэтому защита «эта игра уже открыта в другой вкладке»
   * работает как была.
   * Но есть две лазейки, и лучше знать о них заранее: по команде браузера
   * «Дублировать вкладку» и при восстановлении случайно закрытой вкладки
   * эта память копируется вместе с содержимым. Тогда у двух вкладок имя
   * одинаковое, они считают друг друга собой, и защита молчит: обе сядут
   * за один стол, а выход из любой из них выбросит из партии обеих.
   * Внутри Telegram и в режиме инкогнито доступ к этой памяти иногда
   * запрещён и обрывается ошибкой — тогда берём случайное имя, как раньше.
   */
  function узнатьИмяВкладки() {
    try {
      const сохранённое = window.sessionStorage.getItem(КЛЮЧ_ИМЕНИ_ВКЛАДКИ);
      if (сохранённое) return сохранённое;
      const свежее = придуматьИмя();
      window.sessionStorage.setItem(КЛЮЧ_ИМЕНИ_ВКЛАДКИ, свежее);
      return свежее;
    } catch (сбой) {
      return придуматьИмя();
    }
  }

  const имяВкладки = узнатьИмяВкладки();

  /* Пока играющая вкладка жива, она обновляет отметку времени. Запись
     старше этого срока считается брошенной — например, вкладку закрыли. */
  const СРОК_ЗАНЯТОСТИ = 15 * 1000;
  const ОТМЕТКА_КАЖДЫЕ = 4 * 1000;

  function запомнитьКомнату(код, пропуск) {
    try {
      window.localStorage.setItem(КЛЮЧ_КОМНАТЫ, JSON.stringify({
        код: код, пропуск: пропуск, владелец: имяВкладки, отметка: Date.now()
      }));
    } catch (сбой) {
      /* запрещённая память — не повод ломать игру, просто не вернёмся после перезагрузки */
    }
    обновитьКнопкуВозврата();
  }

  function забытьКомнату() {
    // Чужую запись не стираем: за это время другая вкладка могла начать
    // свою игру, и её ключ возврата нам не принадлежит.
    if (комнатуДержитДругаяВкладка()) return;
    try {
      window.localStorage.removeItem(КЛЮЧ_КОМНАТЫ);
    } catch (сбой) {
      /* ничего страшного */
    }
    обновитьКнопкуВозврата();
  }

  /** Сохранённые код и пропуск или null, если их нет. */
  function вспомнитьКомнату() {
    let текст = null;
    try {
      текст = window.localStorage.getItem(КЛЮЧ_КОМНАТЫ);
    } catch (сбой) {
      return null;
    }
    if (!текст) return null;
    try {
      const разобранное = JSON.parse(текст);
      if (разобранное && разобранное.код && разобранное.пропуск) return разобранное;
    } catch (сбой) {
      /* испорченная запись — считаем, что её нет */
    }
    return null;
  }

  /**
   * Играет ли этой комнатой другая вкладка прямо сейчас. Отметка времени
   * свежая — значит там живой человек за столом, и лезть туда нельзя.
   */
  function комнатуДержитДругаяВкладка() {
    const запись = вспомнитьКомнату();
    if (!запись || !запись.владелец || запись.владелец === имяВкладки) return false;
    return Date.now() - (Number(запись.отметка) || 0) < СРОК_ЗАНЯТОСТИ;
  }

  /** Отметиться: «эта вкладка всё ещё за столом». */
  function отметитьВладение() {
    if (!код || !пропуск) return;
    const запись = вспомнитьКомнату();
    // Чужую запись не трогаем: вдруг за столом уже другая вкладка.
    if (запись && запись.код !== код) return;
    запомнитьКомнату(код, пропуск);
  }

  /* -------------------------------------------------------------------
     Состояние этой вкладки
     ------------------------------------------------------------------- */

  let код = null;              // код комнаты
  let пропуск = null;          // ключ возврата в свою партию
  let версия = 0;              // версия состояния, с которой мы спрашиваем новости
  let вПартии = false;         // идёт ли сейчас наша сетевая партия
  let опросИдёт = false;       // крутится ли длинный опрос
  let связьЕсть = true;        // отвечает ли сервер
  let попытокПодряд = 0;       // сколько раз подряд не достучались
  let последнееСостояние = null;
  let когдаБылоСобытие = 0;    // время последней новости — по нему видно раздумье
  let когдаОтвечалСервер = 0;  // время последнего удачного ответа
  let часовойСвязи = null;     // таймер, освежающий строку связи
  let часовойВладения = null;  // таймер, отмечающий «эта вкладка играет»
  let приветствиеДо = 0;       // до какого времени висит «друг пришёл»
  let ручкаОпроса = null;      // чем прервать висящий длинный опрос

  /* Номер попытки. Каждое новое начало (создали, вошли, вернулись, вышли)
     поднимает его на единицу. Ответ на старый запрос может прийти позже
     нового — например, на медленной связи, — и такой ответ нельзя
     применять: он выбросит человека из свежей комнаты обратно в старую,
     а друг останется за столом навсегда. Поэтому каждый ответ сверяет
     свой номер с текущим и, если отстал, молча выбрасывается. */
  let поколение = 0;

  function новоеПоколение() {
    поколение++;
    return поколение;
  }

  /** Не устарел ли ответ, пока летел. */
  function ответУстарел(моёПоколение) {
    return моёПоколение !== поколение;
  }

  /* -------------------------------------------------------------------
     Запросы к серверу
     ------------------------------------------------------------------- */

  /**
   * Один запрос. Никогда не «падает»: любая беда возвращается обычным
   * ответом с пометкой «связь сорвалась», чтобы её обработали в одном месте.
   */
  function запрос(путь, тело, сколькоЖдать, ручка) {
    const адрес = адресСервера();
    const управление = typeof AbortController !== 'undefined' ? new AbortController() : null;
    const сторож = setTimeout(function () {
      if (управление) управление.abort();
    }, сколькоЖдать || ОБЫЧНОЕ_ОЖИДАНИЕ);

    /* Через ручку запрос можно прервать снаружи. Это нужно при выходе
       в меню: висящий «что нового» вернулся бы в уже удалённую комнату
       и браузер написал бы в консоль красную ошибку 404. */
    if (ручка) {
      ручка.прервать = function () {
        clearTimeout(сторож);
        if (управление) управление.abort();
      };
    }

    const настройки = {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(тело || {})
    };
    if (управление) настройки.signal = управление.signal;

    return fetch(адрес + путь, настройки)
      .then(function (ответ) {
        return ответ.json().catch(function () { return {}; }).then(function (данные) {
          return { ок: ответ.ok, номер: ответ.status, данные: данные || {} };
        });
      })
      .catch(function () {
        return { ок: false, связьСорвалась: true, данные: {} };
      })
      .then(function (итог) {
        clearTimeout(сторож);
        return итог;
      });
  }

  /** Запрос от имени игрока: код и пропуск подставляются сами. */
  function запросОтМеня(путь, тело, сколькоЖдать, ручка) {
    const полное = Object.assign({ код: код, пропуск: пропуск }, тело || {});
    return запрос(путь, полное, сколькоЖдать, ручка);
  }

  /* -------------------------------------------------------------------
     Экраны и надписи
     ------------------------------------------------------------------- */

  function узел(id) {
    return document.getElementById(id);
  }

  function написать(id, текст) {
    const место = узел(id);
    if (место) место.textContent = текст;
  }

  /** Показать или спрятать элемент. */
  function показать(id, видно) {
    const место = узел(id);
    if (место) место.classList.toggle('скрыт', !видно);
  }

  /** Сообщение на экране: пустой текст прячет строку целиком. */
  function сказать(id, текст) {
    написать(id, текст || '');
    показать(id, Boolean(текст));
  }

  /** Мост в js/game.js. Без него сетевой режим бесполезен. */
  function игра() {
    return window.ИграПоСети || null;
  }

  function показатьЭкран(id) {
    const мост = игра();
    if (мост && typeof мост.экран === 'function') мост.экран(id);
  }

  function показатьСвязь(текст, вид) {
    const мост = игра();
    if (мост && typeof мост.показатьСвязь === 'function') мост.показатьСвязь(текст, вид);
  }

  /* -------------------------------------------------------------------
     Строка связи: что происходит прямо сейчас
     ------------------------------------------------------------------- */

  /**
   * Одна строка над столом отвечает на два вопроса сразу: жив ли друг
   * и жива ли наша связь. Пишем словами, без значков — значок «!» человек
   * истолкует как угодно.
   */
  function освежитьСтрокуСвязи() {
    if (!вПартии) return;

    // Молчание дольше длинного опроса — тоже обрыв, даже если ни один
    // запрос ещё не успел сорваться: висящий запрос мог просто повиснуть.
    const давноМолчит = когдаОтвечалСервер > 0 &&
                        Date.now() - когдаОтвечалСервер > МОЛЧАНИЕ_ЭТО_ОБРЫВ;

    if (!связьЕсть || давноМолчит) {
      показатьСвязь('Связь с игрой потеряна. Пробуем восстановить…' +
                    (попытокПодряд > 0 ? ' (попытка ' + попытокПодряд + ')' : ''), 'тревога');
      return;
    }
    const вид = последнееСостояние;
    if (!вид) {
      показатьСвязь('Соединяемся с игрой…', 'ожидание');
      return;
    }
    if (вид.соперникУшёл) {
      показатьСвязь('Друг вышел из игры', 'тревога');
      return;
    }
    if (!вид.соперникНаСвязи) {
      показатьСвязь('Друг пропал со связи — ждём, партия сохранена', 'тревога');
      return;
    }
    // Первые секунды партии показываем сам факт: друг за столом.
    if (Date.now() < приветствиеДо) {
      показатьСвязь('Друг пришёл — играем!');
      return;
    }
    // Ходит друг и молчит уже долго: пусть будет видно, что игра не зависла.
    if (!вид.яХожу && !вид.завершена && Date.now() - когдаБылоСобытие > ДОЛГОЕ_РАЗДУМЬЕ) {
      показатьСвязь('Друг думает…', 'ожидание');
      return;
    }
    показатьСвязь('Друг на связи');
  }

  function запуститьЧасовогоСвязи() {
    if (часовойСвязи !== null) return;
    часовойСвязи = setInterval(освежитьСтрокуСвязи, ЧАСТОТА_СТРОКИ_СВЯЗИ);
  }

  function остановитьЧасовогоСвязи() {
    if (часовойСвязи === null) return;
    clearInterval(часовойСвязи);
    часовойСвязи = null;
  }

  /* -------------------------------------------------------------------
     Приём состояния от сервера
     ------------------------------------------------------------------- */

  /**
   * Принять новое состояние. Отсюда оно уходит в игру одной дверью —
   * так на экране всегда ровно то, что думает сервер.
   */
  function принятьСостояние(вид) {
    if (!вид) return;
    if (typeof вид.версия === 'number') версия = вид.версия;

    const прежнийНомер = последнееСостояние ? последнееСостояние.номерСобытия : -1;
    if (вид.номерСобытия !== прежнийНомер) когдаБылоСобытие = Date.now();
    последнееСостояние = вид;

    if (вид.этап === 'ожидание') {
      /* Сюда попадаем не только в начале. Бывает, что у друга оборвалась
         связь ровно на входе, и сервер откатил вход обратно: мы уже успели
         сесть за стол, а комната снова пуста. Тогда надо вернуть вкладку
         в то же состояние, в каком она была до прихода друга. Иначе его
         вторая попытка войти пройдёт мимо: «мы же уже в партии» — стол
         никто не покажет, и человек до конца просидит на «Ждём друга». */
      if (вПартии) {
        вПартии = false;
        приветствиеДо = 0;
        остановитьЧасовогоСвязи();
        показатьСвязь('');
      }
      показатьОжиданиеДруга(вид);
      return;
    }

    // Партия идёт (или уже доиграна, но комната жива — можно позвать на реванш).
    const мост = игра();
    if (!мост) return;
    if (!вПартии) {
      вПартии = true;
      мост.начать();
      запуститьЧасовогоСвязи();
      // Человек ждал не отчёта о скорости друга, а подтверждения, что тот
      // вообще пришёл. Сначала говорим это, а уже потом всё остальное.
      приветствиеДо = Date.now() + ПОКАЗ_ПРИВЕТСТВИЯ;
    }
    мост.показатьВид(вид);
    освежитьСтрокуСвязи();
  }

  /** Пока второй игрок не пришёл, показываем код и ждём. */
  function показатьОжиданиеДруга(вид) {
    показатьКодКомнаты(вид.код || код || '');
    написать('ожидание-соперника', 'Ждём, когда друг войдёт по коду…');
    показатьЭкран('экран-комнаты');
  }

  /* Что стоит в плашке, пока код не пришёл. Точки помечаются отдельным
     классом: без пометки они выглядят как настоящее значение, и человек
     начинает диктовать другу четыре точки. */
  const ТОЧКИ_ВМЕСТО_КОДА = '····';

  function показатьКодКомнаты(значение) {
    const плашка = узел('код-комнаты');
    if (!плашка) return;
    const настоящий = /^[A-Z0-9]{4,}$/.test(значение || '');
    плашка.textContent = настоящий ? значение : ТОЧКИ_ВМЕСТО_КОДА;
    плашка.classList.toggle('код-игры--ждём', !настоящий);
  }

  /* -------------------------------------------------------------------
     Длинный опрос
     ------------------------------------------------------------------- */

  /** Сколько ждать перед следующей попыткой: чем дольше не выходит, тем реже стучимся. */
  function пауза() {
    const множитель = Math.pow(2, Math.max(0, попытокПодряд - 1));
    return Math.min(МАКСИМАЛЬНАЯ_ПАУЗА, ПАУЗА_ПОСЛЕ_СБОЯ * множитель);
  }

  function связьПотеряна() {
    попытокПодряд++;
    связьЕсть = false;
    освежитьСтрокуСвязи();
  }

  function связьВернулась() {
    попытокПодряд = 0;
    связьЕсть = true;
    когдаОтвечалСервер = Date.now();
    освежитьСтрокуСвязи();
  }

  /**
   * Комната пропала: сервер её уже не помнит (перезапустили, вышли оба,
   * прошло много времени). Играть дальше нечем — честно об этом говорим.
   */
  function комнатаПропала(причина) {
    остановитьОпрос();
    новоеПоколение();
    забытьКомнату();
    код = null;
    пропуск = null;
    последнееСостояние = null;
    const былиВПартии = вПартии;
    вПартии = false;
    приветствиеДо = 0;
    показатьСвязь('');
    остановитьЧасовогоСвязи();
    остановитьЧасовогоВладения();

    const мост = игра();
    if (былиВПартии && мост && typeof мост.вМеню === 'function') мост.вМеню();
    показатьЭкран('экран-друга');
    сказать('сообщение-друга', причина ||
      'Игра закрылась: сервер её больше не помнит. Создайте новую или войдите по коду.');
  }

  function остановитьОпрос() {
    опросИдёт = false;
    // Обрываем висящий запрос: без этого он вернётся в уже закрытую
    // комнату и оставит в консоли красную ошибку.
    if (ручкаОпроса && ручкаОпроса.прервать) ручкаОпроса.прервать();
    ручкаОпроса = null;
  }

  /**
   * Стук в дверь после обрыва. Спрашиваем коротко, «как дела сейчас»,
   * а не «что нового»: длинный опрос придержал бы ответ на полминуты,
   * и всё это время человек читал бы «связь потеряна», хотя она уже есть.
   */
  function достучаться() {
    const моё = поколение;
    запросОтМеня('/состояние', {}).then(function (ответ) {
      if (!опросИдёт || ответУстарел(моё)) return;
      if (ответ.номер === 404) {
        комнатаПропала();
        return;
      }
      if (ответ.связьСорвалась || !ответ.ок) {
        связьПотеряна();
        setTimeout(крутитьОпрос, пауза());
        return;
      }
      связьВернулась();
      if (ответ.данные.состояние) принятьСостояние(ответ.данные.состояние);
      крутитьОпрос();
    });
  }

  /** Спросить сервер о новостях и, что бы ни случилось, спросить снова. */
  function крутитьОпрос() {
    if (!опросИдёт || !код || !пропуск) return;
    if (!связьЕсть) {
      достучаться();
      return;
    }

    const моё = поколение;
    ручкаОпроса = { прервать: null };
    запросОтМеня('/что-нового', { версия: версия }, ОЖИДАНИЕ_ОПРОСА, ручкаОпроса)
      .then(function (ответ) {
      if (!опросИдёт || ответУстарел(моё)) return;

      if (ответ.связьСорвалась) {
        связьПотеряна();
        setTimeout(крутитьОпрос, пауза());
        return;
      }
      if (ответ.номер === 404) {
        комнатаПропала();
        return;
      }
      if (!ответ.ок) {
        // Сервер жив, но чем-то недоволен. Связь есть, поэтому просто
        // подождём и спросим снова — обычно это временная беда.
        связьПотеряна();
        setTimeout(крутитьОпрос, пауза());
        return;
      }

      связьВернулась();
      if (ответ.данные.комнатыНет) {
        комнатаПропала();
        return;
      }
      if (ответ.данные.изменилось && ответ.данные.состояние) {
        принятьСостояние(ответ.данные.состояние);
      }
      крутитьОпрос();
    });
  }

  function запуститьОпрос() {
    if (опросИдёт) return;
    опросИдёт = true;
    крутитьОпрос();
  }

  /* -------------------------------------------------------------------
     Создание игры, вход и возвращение
     ------------------------------------------------------------------- */

  /** Проверить адрес перед любой попыткой соединиться. Вернёт false, если играть нельзя. */
  function адресГодится(кудаПисать) {
    const беда = почемуАдресНеПодходит(адресСервера());
    if (!беда) return true;
    сказать(кудаПисать, беда);
    return false;
  }

  /** Человеческое объяснение, почему сервер недоступен. */
  const СЕРВЕР_МОЛЧИТ = 'Сервер игры не отвечает. Проверьте, что он запущен ' +
    'и что адрес игры указан верно.';

  function создатьИгру() {
    if (!адресГодится('сообщение-друга')) return;
    сказать('сообщение-друга', 'Создаём игру…');
    // Старый код с прошлой игры показывать нельзя: его уже никто не ждёт.
    показатьКодКомнаты('');
    сказать('сообщение-копирования', '');

    const моё = новоеПоколение();
    запрос('/создать', {}).then(function (ответ) {
      if (ответУстарел(моё)) return;   // человек уже ушёл в другую игру
      if (ответ.связьСорвалась) {
        сказать('сообщение-друга', СЕРВЕР_МОЛЧИТ);
        return;
      }
      if (!ответ.ок || !ответ.данные.код) {
        сказать('сообщение-друга', ответ.данные.ошибка || 'Сервер не смог создать игру.');
        return;
      }
      сказать('сообщение-друга', '');
      начатьЖизньВКомнате(ответ.данные.код, ответ.данные.пропуск, ответ.данные.состояние);
    });
  }

  /** Привести набранный код к виду, который понимает сервер. */
  function очиститьКод(что) {
    return String(что || '').toUpperCase().replace(/[^A-Z0-9]/g, '').slice(0, 6);
  }

  function войтиПоКоду() {
    if (!адресГодится('сообщение-входа')) return;
    const поле = узел('поле-кода');
    const набранный = очиститьКод(поле ? поле.value : '');
    if (набранный.length < 4) {
      сказать('сообщение-входа', 'Код состоит из четырёх знаков — наберите его целиком.');
      return;
    }
    сказать('сообщение-входа', 'Входим в игру…');

    const моё = новоеПоколение();
    запрос('/войти', { код: набранный }).then(function (ответ) {
      if (ответУстарел(моё)) return;
      if (ответ.связьСорвалась) {
        сказать('сообщение-входа', СЕРВЕР_МОЛЧИТ);
        return;
      }
      if (!ответ.ок || !ответ.данные.пропуск) {
        сказать('сообщение-входа', ответ.данные.ошибка ||
          'Войти не получилось. Проверьте код — возможно, игру уже начали без вас.');
        return;
      }
      сказать('сообщение-входа', '');
      начатьЖизньВКомнате(ответ.данные.код || набранный, ответ.данные.пропуск,
                          ответ.данные.состояние);
    });
  }

  /** Мы в комнате: запоминаем ключи, показываем первое состояние и слушаем новости. */
  function начатьЖизньВКомнате(новыйКод, новыйПропуск, состояние) {
    остановитьОпрос();          // старый опрос мог ещё висеть на прошлой комнате
    новоеПоколение();           // всё, что летело раньше, теперь устарело
    код = новыйКод;
    пропуск = новыйПропуск;
    версия = 0;
    попытокПодряд = 0;
    связьЕсть = true;
    последнееСостояние = null;
    когдаБылоСобытие = Date.now();
    когдаОтвечалСервер = Date.now();
    приветствиеДо = 0;
    запомнитьКомнату(код, пропуск);
    запуститьЧасовогоВладения();
    if (состояние) принятьСостояние(состояние);
    else показатьЭкран('экран-комнаты');
    запуститьОпрос();
  }

  /* Пока эта вкладка за столом, она регулярно отмечается в памяти
     браузера. По этой отметке вторая вкладка понимает, что место занято. */
  function запуститьЧасовогоВладения() {
    if (часовойВладения !== null) return;
    часовойВладения = setInterval(отметитьВладение, ОТМЕТКА_КАЖДЫЕ);
  }

  function остановитьЧасовогоВладения() {
    if (часовойВладения === null) return;
    clearInterval(часовойВладения);
    часовойВладения = null;
  }

  /**
   * Вернуться в партию, начатую до перезагрузки страницы. Спрашиваем сервер,
   * жива ли комната: если нет — молча забываем ключи, чтобы не предлагать
   * человеку вернуться в никуда.
   */
  function попробоватьВернуться(сСообщением) {
    const сохранённое = вспомнитьКомнату();
    if (!сохранённое) return;
    if (почемуАдресНеПодходит(адресСервера())) return;

    // За этим столом уже сидит другая вкладка. Сесть туда же нельзя:
    // выход из второй вкладки выбросил бы из партии и первую.
    if (комнатуДержитДругаяВкладка()) {
      сказать('сообщение-друга', 'Эта игра уже открыта в другой вкладке — играйте там. ' +
        'Здесь можно создать новую игру или войти к другому другу.');
      return;
    }

    if (сСообщением) сказать('сообщение-друга', 'Возвращаемся в вашу игру…');

    /* Ключи от комнаты нарочно не кладём в «код» и «пропуск», пока сервер
       не подтвердил, что партия жива, — спрашиваем о ней напрямую. Раньше
       мы занимали место сразу, и выход, нажатый в эти секунды ожидания,
       уходил на сервер по-настоящему: человек всего лишь передумал
       возвращаться, а партия рвалась у обоих. */
    const моё = новоеПоколение();
    запрос('/состояние', { код: сохранённое.код, пропуск: сохранённое.пропуск })
        .then(function (ответ) {
      // Пока ответ шёл, человек мог войти в другую игру. Такой ответ
      // применять нельзя: он выкинет его обратно в старую комнату,
      // а друг останется за столом один и навсегда.
      if (ответУстарел(моё)) return;
      if (ответ.связьСорвалась) {
        if (сСообщением) сказать('сообщение-друга', СЕРВЕР_МОЛЧИТ);
        return;
      }
      if (!ответ.ок || !ответ.данные.состояние) {
        // Комнаты нет — ключи бесполезны. За столом мы так и не сели,
        // поэтому чистить нечего, кроме памяти браузера.
        забытьКомнату();
        if (сСообщением) сказать('сообщение-друга', 'Прошлая игра уже закрыта. Создайте новую.');
        return;
      }
      if (сСообщением) сказать('сообщение-друга', '');
      начатьЖизньВКомнате(сохранённое.код, сохранённое.пропуск, ответ.данные.состояние);
    });
  }

  /* -------------------------------------------------------------------
     Уход из партии
     ------------------------------------------------------------------- */

  /**
   * Выйти из партии: сказать серверу (чтобы друг сразу увидел уход),
   * погасить опрос и забыть ключи. Вызывать можно всегда — если сетевой
   * партии нет, ничего не произойдёт.
   */
  function покинутьПартию() {
    остановитьОпрос();
    остановитьЧасовогоСвязи();
    остановитьЧасовогоВладения();
    новоеПоколение();       // всё, что ещё летит, к этой партии уже не относится
    показатьСвязь('');
    вПартии = false;
    последнееСостояние = null;
    приветствиеДо = 0;
    if (!код || !пропуск) return;
    const уходящийКод = код;
    const уходящийПропуск = пропуск;
    код = null;
    пропуск = null;
    забытьКомнату();
    // Ответ нам уже не нужен: мы уходим в любом случае.
    запрос('/выйти', { код: уходящийКод, пропуск: уходящийПропуск });
  }

  /* -------------------------------------------------------------------
     Кнопки
     ------------------------------------------------------------------- */

  /**
   * Показать в меню кнопку возврата, если есть недоигранная партия.
   * Живость комнаты здесь не проверяем: лишний запрос при каждом открытии
   * меню того не стоит, а если игра уже закрыта, человеку об этом скажут
   * сразу после нажатия.
   */
  function обновитьКнопкуВозврата() {
    const кнопка = узел('кнопка-вернуться-в-игру');
    if (!кнопка) return;
    const естьЧтоПродолжить = Boolean(вспомнитьКомнату()) && !комнатуДержитДругаяВкладка();
    кнопка.classList.toggle('скрыт', !естьЧтоПродолжить);
  }

  function открытьЭкранДруга() {
    сказать('сообщение-друга', '');
    показатьЭкран('экран-друга');
    // Адрес проверяем сразу: пусть человек узнает о беде до того,
    // как начнёт создавать игру и звать друга.
    const беда = почемуАдресНеПодходит(адресСервера());
    if (беда) {
      сказать('сообщение-друга', беда);
      return;
    }
    // Есть недоигранная партия — попробуем вернуться в неё сами.
    if (вспомнитьКомнату()) попробоватьВернуться(true);
  }

  /* -------------------------------------------------------------------
     Копирование кода
     ------------------------------------------------------------------- */

  const ПОКАЗ_ОТВЕТА_КНОПКИ = 2000;   // сколько кнопка держит ответ вместо названия
  let обычнаяНадписьКнопки = '';
  let таймерНадписи = null;

  /**
   * Ответить прямо на кнопке. Без ответа человек не понимает, сработало ли
   * нажатие, и жмёт ещё раз.
   */
  function ответитьНаКнопке(текст) {
    const кнопка = узел('кнопка-копировать-код');
    if (!кнопка) return;
    if (!обычнаяНадписьКнопки) обычнаяНадписьКнопки = кнопка.textContent;
    кнопка.textContent = текст;
    if (таймерНадписи !== null) clearTimeout(таймерНадписи);
    таймерНадписи = setTimeout(function () {
      таймерНадписи = null;
      кнопка.textContent = обычнаяНадписьКнопки;
    }, ПОКАЗ_ОТВЕТА_КНОПКИ);
  }

  /**
   * Старый способ копирования — через невидимое поле. Нужен там, где нового
   * буфера обмена нет: он работает только на защищённых страницах, а внутри
   * Telegram встроенный браузер иногда не даёт и его.
   */
  function скопироватьЧерезПоле(текст) {
    try {
      const поле = document.createElement('textarea');
      поле.value = текст;
      поле.setAttribute('readonly', '');
      поле.style.position = 'fixed';
      поле.style.top = '-1000px';
      document.body.appendChild(поле);
      поле.select();
      // Без этой строки на iPhone выделение не срабатывает.
      if (поле.setSelectionRange) поле.setSelectionRange(0, текст.length);
      const вышло = document.execCommand && document.execCommand('copy');
      document.body.removeChild(поле);
      return Boolean(вышло);
    } catch (сбой) {
      return false;
    }
  }

  /** Положить текст в буфер обмена. Сначала новым способом, потом старым. */
  function положитьВБуфер(текст) {
    const буфер = window.navigator && window.navigator.clipboard;
    if (буфер && typeof буфер.writeText === 'function') {
      try {
        return буфер.writeText(текст).then(
          function () { return true; },
          function () { return скопироватьЧерезПоле(текст); }
        );
      } catch (сбой) {
        return Promise.resolve(скопироватьЧерезПоле(текст));
      }
    }
    return Promise.resolve(скопироватьЧерезПоле(текст));
  }

  function скопироватьКод() {
    if (!код) {
      сказать('сообщение-копирования', 'Код ещё не пришёл — подождите секунду.');
      return;
    }
    положитьВБуфер(код).then(function (вышло) {
      if (вышло) {
        ответитьНаКнопке('Код скопирован');
        сказать('сообщение-копирования', 'Код в буфере — вставьте его другу в переписку.');
        return;
      }
      // Молчать нельзя: человек решит, что скопировалось, и отправит пустоту.
      ответитьНаКнопке('Скопировать не вышло');
      сказать('сообщение-копирования',
        'Скопировать не получилось — телефон не дал доступ к буферу обмена. ' +
        'Продиктуйте другу код: ' + код);
    });
  }

  function открытьЭкранВхода() {
    сказать('сообщение-входа', '');
    const поле = узел('поле-кода');
    if (поле) поле.value = '';
    показатьЭкран('экран-входа');
    if (поле) поле.focus();
  }

  function отменитьКомнату() {
    покинутьПартию();
    сказать('сообщение-друга', '');
    сказать('сообщение-копирования', '');
    показатьКодКомнаты('');   // чужой старый код в плашке никому не нужен
    показатьЭкран('экран-друга');
  }

  /**
   * Бросить начатую попытку вернуться в партию. Серверу мы при этом ничего
   * не говорим и ключи возврата не стираем: партия жива, друг за столом,
   * вернуться можно в любой момент. Единственное, что делаем, — помечаем
   * улетевший вопрос о комнате устаревшим, иначе его ответ через секунду
   * затащил бы человека за стол прямо из меню.
   */
  function отменитьВозврат() {
    новоеПоколение();
  }

  /**
   * «Назад» на экране «Игра с другом». Здесь два разных «выхода», и путать
   * их нельзя. За столом кнопка «В меню» — это настоящий уход из партии,
   * и она честно предупреждает, что друг останется один. А на этом экране
   * человек за стол ещё не сел: сюда попадают из меню, и как только возврат
   * удался, экран сам сменяется на стол или на плашку с кодом. Значит,
   * «Назад» здесь означает «передумал возвращаться прямо сейчас» —
   * партию не рвём, ключи оставляем, кнопка возврата в меню остаётся.
   */
  function вернутьсяВМеню() {
    // Если мы всё-таки за столом (так сюда не попасть, но пусть будет
    // надёжно) — это честный выход, и друга надо предупредить.
    if (вПартии || (код && пропуск)) покинутьПартию();
    else отменитьВозврат();
    // Иначе «Возвращаемся в вашу игру…» так и висит на скрытом экране.
    сказать('сообщение-друга', '');
    обновитьКнопкуВозврата();
    показатьЭкран('экран-меню');
  }

  function накнопку(id, действие) {
    const кнопка = узел(id);
    if (!кнопка) {
      console.warn('Игра вдвоём: не нашёл кнопку «' + id + '». ' +
                   'Скорее всего, браузер показывает старую страницу — обновите её (Ctrl+F5).');
      return;
    }
    кнопка.addEventListener('click', действие);
  }

  function подключить() {
    накнопку('кнопка-с-другом', открытьЭкранДруга);
    накнопку('кнопка-вернуться-в-игру', открытьЭкранДруга);
    накнопку('кнопка-создать-игру', создатьИгру);
    накнопку('кнопка-войти-по-коду', открытьЭкранВхода);
    накнопку('кнопка-друг-назад', вернутьсяВМеню);
    накнопку('кнопка-копировать-код', скопироватьКод);
    накнопку('кнопка-комната-отмена', отменитьКомнату);
    накнопку('кнопка-войти', войтиПоКоду);
    накнопку('кнопка-вход-назад', открытьЭкранДруга);

    // Телефон сам сообщает, что связь пропала или вернулась. Это самый
    // быстрый сигнал: ждать, пока оборвётся висящий запрос, не нужно.
    window.addEventListener('offline', function () {
      if (!вПартии) return;
      связьЕсть = false;
      освежитьСтрокуСвязи();
    });
    window.addEventListener('online', function () {
      if (!вПартии || !код || !пропуск) return;
      // Сеть вернулась — не ждём паузы, спрашиваем состояние сразу.
      const моё = поколение;
      запросОтМеня('/состояние', {}).then(function (ответ) {
        // Пока ответ шёл, человек мог выйти и начать новую игру. Тогда это
        // рассказ о брошенной комнате, и показывать его нельзя.
        if (ответУстарел(моё)) return;
        if (!ответ.ок || !ответ.данные.состояние) return;
        связьВернулась();
        принятьСостояние(ответ.данные.состояние);
      });
    });

    const поле = узел('поле-кода');
    if (поле) {
      // Телефон норовит писать строчными и «исправлять» код в слово.
      поле.addEventListener('input', function () {
        const исправленный = очиститьКод(поле.value);
        if (поле.value !== исправленный) поле.value = исправленный;
      });
      поле.addEventListener('keydown', function (событие) {
        if (событие.key === 'Enter') войтиПоКоду();
      });
    }

    /* В разметке кнопка возврата спрятана. Показать её при первой загрузке
       некому, кроме этой строки: дальше её включает и выключает работа с
       памятью браузера, а перезагрузка страницы — как раз тот случай,
       ради которого кнопку и делали. */
    обновитьКнопкуВозврата();
  }

  /* -------------------------------------------------------------------
     Наружу — только то, чем пользуется js/game.js
     ------------------------------------------------------------------- */

  window.Сеть = {
    /**
     * Отправить намерение игрока. Обещание никогда не срывается:
     * при любой беде вернётся { ошибкаСвязи: true }, и игра не сломается.
     */
    отправитьХод: function (намерение) {
      if (!код || !пропуск) {
        return Promise.resolve({ принято: false, причина: 'Вы сейчас не в игре с другом' });
      }
      const моё = поколение;
      return запросОтМеня('/ход', намерение || {}).then(function (ответ) {
        // Ответ мог опоздать: человек уже вышел и сел за новый стол.
        // Особенно опасен запоздавший «комнаты нет» — он выбросил бы
        // игрока из свежей партии, а друг остался бы за столом один.
        // Пустой ответ игра переживает: она проверяет его на «ничего».
        if (ответУстарел(моё)) return;
        if (ответ.связьСорвалась) {
          связьПотеряна();
          return { ошибкаСвязи: true };
        }
        if (ответ.номер === 404) {
          комнатаПропала();
          return { ошибкаСвязи: true };
        }
        связьВернулась();
        if (ответ.данные.состояние) принятьСостояние(ответ.данные.состояние);
        return {
          принято: Boolean(ответ.данные.принято),
          причина: ответ.данные.причина || ответ.данные.ошибка || null
        };
      });
    },

    покинутьПартию: покинутьПартию,

    /** Идёт ли сейчас сетевая партия — нужно для проверок. */
    вИгре: function () { return вПартии; },

    /** Адрес сервера, с которым работаем. Пригодится при разборе жалоб. */
    адрес: адресСервера
  };

  // Разметка к этому времени готова: файл подключён в конце страницы.
  подключить();

})();
