/* =====================================================================
   Игра вдвоём: разговор с сервером.

   Этот файл — единственное место, которое знает про сеть. Правил игры
   здесь нет вовсе: их считает сервер, а мы только отправляем намерения
   («хочу сходить этой картой») и показываем то, что он ответил.

   Как всё устроено:
     1. Человек создаёт игру — сервер выдаёт код из четырёх знаков
        и пропуск. Код диктуют другу, пропуск храним у себя.
     2. Друг входит по коду, партия начинается.
     3. Дальше работает «длинный опрос»: мы спрашиваем сервер
        «что нового?», он придерживает ответ, пока за столом что-нибудь
        не произойдёт, и отвечает новым состоянием. Ответил — спрашиваем
        снова, и так всю партию.

   Почему пропуск важнее кода: код перестаёт работать, как только
   в комнату вошли двое. Вернуться в свою партию после обрыва связи
   можно только по пропуску, поэтому он лежит в памяти браузера.

   Где проходит граница с js/game.js. Стол с картами этот файл не рисует
   совсем: готовое состояние уходит в js/game.js через мост ИграПоСети —
   там его превращают в карты, подсказки и кнопки. Зато служебные экраны
   сетевого режима — «Игра с другом», плашка с кодом, вход по коду, — со
   всеми их надписями и сообщениями пишет прямо этот файл: в одиночной
   игре таких экранов нет, и js/game.js про них ничего не знает. Само
   переключение между экранами и строку связи над столом файл тоже просит
   у js/game.js через мост, а не трогает своими руками.
   ===================================================================== */

'use strict';

(function () {

  /* -------------------------------------------------------------------
     Адрес сервера
     ------------------------------------------------------------------- */

  /* Главный способ задать адрес — в самом адресе страницы:
       index.html?сервер=https://адрес-сервера
     Так его можно поменять в настройках бота (GAME_URL), не трогая код
     и не поднимая номер версии файла.

     Второй способ — вписать адрес руками прямо в игре (экран «Игра
     с другом», кнопка «Указать адрес сервера»). Он появился потому, что
     первый способ иногда отказывает целиком: адрес быстрого туннеля
     меняется при каждом запуске, а старая ссылка из закладки ведёт
     в никуда. Раньше человеку в этом случае было некуда деться — все
     объяснения советовали взять свежую ссылку у бота, и если бот молчал,
     игра вдвоём кончалась.

     Кто из двух адресов главнее. Сначала главным был адрес из ссылки —
     всегда. И это оставляло человека в тупике ровно там, где вписанный
     адрес и придумали: игра открыта из закладки или из старого сообщения
     бота, в ссылке торчит мёртвый хвостик «?сервер=», выкинуть его внутри
     Telegram нечем — и вписанный живой адрес не спасал.

     Теперь правило другое: ЖИВОЙ ПОБЕЖДАЕТ МЁРТВОГО.
       — адрес из ссылки отвечает → играем по нему. Он остаётся главным,
         и это важно: только свежая ссылка позволяет переехать на новый
         сервер, иначе однажды вписанный адрес держал бы человека вечно;
       — адрес из ссылки молчит, а вписанный отвечает → играем по вписанному;
       — молчат оба → остаёмся на адресе из ссылки и объясняем беду;
       — в ссылке адреса нет → играем по вписанному;
       — нет ни того, ни другого → запасной адрес из константы ниже.

     Кто живой, выясняем коротким стуком в дверь. Стучимся только когда
     спорить есть о чём — адреса два и они разные. У большинства игроков
     вписанного адреса нет вовсе, спора нет, и запуск не тормозит ни на миг.

     Константа ниже — последний запасной вариант, для игры на своём
     компьютере. */
  const АДРЕС_ПО_УМОЛЧАНИЮ = 'http://127.0.0.1:8765';

  /* Где лежит вписанный руками адрес сервера. */
  const КЛЮЧ_АДРЕСА = 'подкидной-дурак:адрес-сервера';

  const ОБЫЧНОЕ_ОЖИДАНИЕ = 10 * 1000;      // сколько ждём короткий ответ
  const ОЖИДАНИЕ_ОПРОСА = 40 * 1000;       // длинный опрос сервер держит 25 секунд
  const ПАУЗА_ПОСЛЕ_СБОЯ = 1000;           // первая пауза перед повтором
  const МАКСИМАЛЬНАЯ_ПАУЗА = 10 * 1000;    // дальше паузы не растут
  const ДОЛГОЕ_РАЗДУМЬЕ = 10 * 1000;       // после этого пишем «друг думает»
  const ПОКАЗ_ПРИВЕТСТВИЯ = 4000;          // сколько висит «друг пришёл»
  const ЧАСТОТА_СТРОКИ_СВЯЗИ = 1000;       // как часто освежаем надпись о связи
  /* Сервер отвечает на длинный опрос не позже чем через 25 секунд, даже
     когда новостей нет. Значит, молчание дольше этого — уже не тишина
     за столом, а оборванная связь, и человеку пора об этом сказать.
     Десять секунд сверху — запас на медленную сеть, чтобы не пугать
     человека тревогой на ровном месте. */
  const МОЛЧАНИЕ_ЭТО_ОБРЫВ = 35 * 1000;

  /* Где лежит ключ от своей партии. Пропуск — это не пароль от чего-то
     ценного: он открывает одну комнату с картами и живёт минуты. */
  const КЛЮЧ_КОМНАТЫ = 'подкидной-дурак:комната';

  /* Как выглядит рабочий адрес: начало, имя сервера, необязательный порт
     и путь. Пробелов и лишних слов быть не должно. Разбираем сами, а не
     через URL: так проверка одинаково работает и в браузере, и в имитации
     страницы, где встроенного разбора адресов может не быть. */
  const ПОХОЖЕ_НА_АДРЕС = /^https?:\/\/[^\s/:?#]+(:\d+)?(\/[^\s?#]*)?$/i;

  /* Свой компьютер и домашняя сеть: туда ходят по обычному http —
     защищённого https там обычно просто нет. Нужно, чтобы дописать
     недостающее начало адреса самим. */
  const АДРЕС_СВОЕГО_КОМПЬЮТЕРА =
    /^(localhost|127\.\d+\.\d+\.\d+|0\.0\.0\.0|\[[^\]]+\]|10\.\d+\.\d+\.\d+|192\.168\.\d+\.\d+|172\.(1[6-9]|2\d|3[01])\.\d+\.\d+)(:\d+)?$/i;

  /**
   * Привести вписанный адрес к рабочему виду.
   * Прощаем лишние пробелы, хвостовой знак «/» и забытое начало «https://»,
   * а если из написанного адреса не выходит — честно говорим, чего не хватает.
   * Возвращаем { адрес, беда }: либо готовый адрес, либо объяснение.
   */
  function привестиАдрес(что) {
    let текст = String(что === null || что === undefined ? '' : что).trim();
    if (!текст) return { адрес: '', беда: 'Адрес пустой — впишите его целиком.' };

    текст = текст.replace(/^\/+/, '').replace(/\/+$/, '');   // «//адрес» и «адрес/» — обычные описки

    if (!/^https?:\/\//i.test(текст)) {
      // Начало вида «ws://» или «ftp://» дописать нельзя — тут нужен человек.
      if (/^[a-zа-яё]+:\/\//i.test(текст)) {
        return { адрес: '', беда: 'Адрес должен начинаться с https:// или http://, ' +
                                  'а начинается по-другому: «' + текст + '».' };
      }
      // Начала нет вовсе — дописываем сами. Для своего компьютера это
      // http://, для всего остального https://: туннели и опубликованные
      // сайты всегда защищённые.
      const имяСервера = текст.split('/')[0];
      текст = (АДРЕС_СВОЕГО_КОМПЬЮТЕРА.test(имяСервера) ? 'http://' : 'https://') + текст;
    }

    if (!ПОХОЖЕ_НА_АДРЕС.test(текст)) {
      return { адрес: '', беда: 'Это не похоже на адрес сервера: «' + текст + '». ' +
                                'Нужно что-то вроде https://имя-сервера.trycloudflare.com ' +
                                'или http://127.0.0.1:8790 — одной строкой, без пробелов.' };
    }
    return { адрес: текст, беда: null };
  }

  /** Что стоит в хвостике «?сервер=» самой ссылки на игру. */
  function адресИзСсылки() {
    try {
      const разбор = new URLSearchParams(window.location.search);
      // Русское название удобно человеку, латинское — тому, кто правит
      // настройки бота в консоли. Принимаем оба.
      return разбор.get('сервер') || разбор.get('server') || '';
    } catch (сбой) {
      return '';
    }
  }

  /* Вписанный адрес держим ещё и здесь. Память браузера бывает запрещена
     (режим инкогнито, встроенный браузер Telegram), и тогда сохранить
     адрес не выйдет — но хотя бы до перезагрузки страницы человек должен
     сыграть, а не читать отказ. */
  let вписанныйАдрес = '';

  /** Адрес, вписанный руками и сохранённый в памяти браузера. */
  function сохранённыйАдрес() {
    try {
      return (window.localStorage.getItem(КЛЮЧ_АДРЕСА) || '').trim();
    } catch (сбой) {
      return '';
    }
  }

  /** Запомнить вписанный адрес. Отвечает, легло ли в память браузера. */
  function запомнитьАдрес(адрес) {
    вписанныйАдрес = адрес;
    try {
      window.localStorage.setItem(КЛЮЧ_АДРЕСА, адрес);
      return true;
    } catch (сбой) {
      return false;
    }
  }

  /** Забыть вписанный адрес и вернуться к тому, что в ссылке. */
  function забытьАдрес() {
    вписанныйАдрес = '';
    try {
      window.localStorage.removeItem(КЛЮЧ_АДРЕСА);
    } catch (сбой) {
      /* нечего было забывать */
    }
  }

  /** Оба возможных адреса, уже приведённые к рабочему виду. */
  function кандидаты() {
    return {
      ссылка: привестиАдрес(адресИзСсылки()).адрес,
      вписан: привестиАдрес(сохранённыйАдрес() || вписанныйАдрес).адрес
    };
  }

  /* Итог спора двух адресов: кто из них ответил и кого в итоге выбрали.
     Держим до перезагрузки страницы — стучаться в дверь на каждый чих
     незачем. Сбрасывается сам, как только один из адресов изменился
     (человек вписал другой или стёр вписанный). */
  let итогСпора = null;    // { ссылка, вписан, адрес, ссылкаЖива, вписанныйЖив }
  let забег = null;        // идущая прямо сейчас проверка: { ссылка, вписан, обещание }

  /** Есть ли о чём спорить: адреса два и они разные. */
  function естьСпор() {
    const кто = кандидаты();
    return Boolean(кто.ссылка && кто.вписан && кто.ссылка !== кто.вписан);
  }

  /** Годится ли добытый итог для нынешней пары адресов. */
  function итогГодится() {
    const кто = кандидаты();
    return Boolean(итогСпора && итогСпора.ссылка === кто.ссылка &&
                   итогСпора.вписан === кто.вписан);
  }

  /** Забыть, кто победил: адреса изменились, надо выяснять заново. */
  function забытьИтогСпора() {
    итогСпора = null;
    забег = null;
  }

  /**
   * Адрес сервера. Спор уже решён — берём победителя. Не решён (или спорить
   * не о чем) — отвечаем сразу, не задерживая игру: адрес из ссылки, потом
   * вписанный, потом запасной.
   */
  function адресСервера() {
    if (итогГодится()) return итогСпора.адрес;
    const кто = кандидаты();
    if (кто.ссылка) return кто.ссылка;
    if (кто.вписан) return кто.вписан;
    return АДРЕС_ПО_УМОЛЧАНИЮ;
  }

  /** Откуда взялся нынешний адрес: 'ссылка' | 'вписан' | 'запасной'. */
  function откудаАдрес() {
    const кто = кандидаты();
    const адрес = адресСервера();
    if (кто.ссылка && кто.ссылка === адрес) return 'ссылка';
    if (кто.вписан && кто.вписан === адрес) return 'вписан';
    return 'запасной';
  }

  /**
   * Выяснить, какой из двух адресов живой, и выбрать его.
   * Стучимся в оба разом, а не по очереди: так ожидание равно одному
   * стуку, а не двум. Ответ всегда обещание с выбранным адресом.
   */
  function решитьСпорАдресов() {
    if (итогГодится()) return Promise.resolve(итогСпора.адрес);

    const кто = кандидаты();
    // Спорить не о чем: адрес один (или их нет вовсе). Никуда не стучимся.
    if (!кто.ссылка || !кто.вписан || кто.ссылка === кто.вписан) {
      return Promise.resolve(адресСервера());
    }
    // Такой же забег уже идёт — ждём его, второй раз сервер не тревожим.
    if (забег && забег.ссылка === кто.ссылка && забег.вписан === кто.вписан) {
      return забег.обещание;
    }

    const обещание = Promise.all([отвечаетЛиАдрес(кто.ссылка), отвечаетЛиАдрес(кто.вписан)])
        .then(function (ответы) {
      const ссылкаЖива = ответы[0];
      const вписанныйЖив = ответы[1];
      /* Уступает адрес из ссылки только в одном случае: сам молчит,
         а вписанный отвечает. Во всех остальных он главный. */
      const адрес = (!ссылкаЖива && вписанныйЖив) ? кто.вписан : кто.ссылка;
      // Пока стучались, человек мог вписать другой адрес — тогда наш
      // итог уже про вчерашний день, и записывать его нельзя.
      const сейчас = кандидаты();
      if (сейчас.ссылка === кто.ссылка && сейчас.вписан === кто.вписан) {
        итогСпора = {
          ссылка: кто.ссылка, вписан: кто.вписан, адрес: адрес,
          ссылкаЖива: ссылкаЖива, вписанныйЖив: вписанныйЖив
        };
        забег = null;
      }
      return адресСервера();
    });

    забег = { ссылка: кто.ссылка, вписан: кто.вписан, обещание: обещание };
    return обещание;
  }

  /**
   * Сделать дело тогда, когда адрес окончательно выбран. Спорить не о чем —
   * делаем прямо сейчас, в той же строке: обычный запуск по хорошей ссылке
   * не должен ждать ни секунды. Спор есть — сначала выясняем, кто живой.
   *
   * Если дело начато нажатием кнопки, её имя стоит передать: кнопка скажет,
   * чего ждём, и на время ожидания перестанет принимать нажатия — двойной
   * тап на телефоне иначе отправил бы два запроса подряд.
   */
  function приВыбранномАдресе(идКнопки, дело) {
    if (итогГодится() || !естьСпор()) {
      дело();
      return;
    }
    if (идКнопки) занятьКнопку(идКнопки, 'Проверяем адрес…');
    решитьСпорАдресов().then(function () {
      if (идКнопки) освободитьКнопку(идКнопки);
      дело();
    });
  }

  /**
   * Пропустит ли браузер запрос по такому адресу. Защищённая страница
   * (а в Telegram она всегда защищённая) не имеет права обращаться
   * к незащищённому адресу — браузер запрещает это молча.
   */
  function браузерЗапретит(адрес) {
    return window.location.protocol === 'https:' && /^http:\/\//i.test(адрес);
  }

  /**
   * Почему по этому адресу играть не выйдет. Проверяем до первой попытки:
   * иначе браузер скажет невнятное «не удалось подключиться», и человек
   * будет искать причину весь вечер.
   */
  function почемуАдресНеПодходит(адрес) {
    if (!/^https?:\/\//i.test(адрес)) {
      return 'Адрес сервера должен начинаться с http:// или https://, а сейчас это «' +
             адрес + '». Впишите адрес заново: кнопка «Указать адрес сервера» ниже.';
    }
    if (браузерЗапретит(адрес)) {
      /* Про запрет браузера на смешанные адреса человеку знать незачем —
         ему нужно знать, какой адрес подойдёт и где его вписать. */
      return 'Игра вдвоём по этой ссылке не заработает: сервер в ней записан как ' +
             адрес + ', а отсюда игра может стучаться только по адресам на https://. ' +
             'Обычно это ссылка туннеля вида https://имя-сервера.trycloudflare.com. ' +
             КАК_ВПИСАТЬ_АДРЕС + ' ' + КАК_ВЗЯТЬ_ССЫЛКУ +
             ' Игра против бота работает и здесь.';
    }
    return null;
  }

  /* -------------------------------------------------------------------
     Память о своей комнате
     ------------------------------------------------------------------- */

  /* Своё имя этой открытой страницы. Память браузера одна на все вкладки,
     поэтому в записи о комнате отмечено, какая вкладка сейчас за столом:
     иначе вторая вкладка садится на то же место, а её выход выкидывает
     из партии и первую — друг видит «Друг вышел», хотя человек играет. */
  const КЛЮЧ_ИМЕНИ_ВКЛАДКИ = 'подкидной-дурак:вкладка';

  function придуматьИмя() {
    return Math.random().toString(36).slice(2) + Date.now().toString(36);
  }

  /**
   * Имя берём из памяти самой вкладки (sessionStorage). Она у каждой вкладки
   * своя и переживает перезагрузку страницы — а это ровно то, что нужно:
   * после обновления вкладка узнаёт собственную запись о комнате и зовёт
   * вернуться в игру. Со случайным именем при каждой загрузке она принимала
   * себя же за соседнюю вкладку и первые пятнадцать секунд отказывалась
   * возвращаться в свою партию.
   * Вкладка, открытая обычным способом, чужой памяти не наследует, имя
   * получает другое, поэтому защита «эта игра уже открыта в другой вкладке»
   * работает как была.
   * Но есть две лазейки, и лучше знать о них заранее: по команде браузера
   * «Дублировать вкладку» и при восстановлении случайно закрытой вкладки
   * эта память копируется вместе с содержимым. Тогда у двух вкладок имя
   * одинаковое, они считают друг друга собой, и защита молчит: обе сядут
   * за один стол, а выход из любой из них выбросит из партии обеих.
   * Внутри Telegram и в режиме инкогнито доступ к этой памяти иногда
   * запрещён и обрывается ошибкой — тогда берём случайное имя, как раньше.
   */
  function узнатьИмяВкладки() {
    try {
      const сохранённое = window.sessionStorage.getItem(КЛЮЧ_ИМЕНИ_ВКЛАДКИ);
      if (сохранённое) return сохранённое;
      const свежее = придуматьИмя();
      window.sessionStorage.setItem(КЛЮЧ_ИМЕНИ_ВКЛАДКИ, свежее);
      return свежее;
    } catch (сбой) {
      return придуматьИмя();
    }
  }

  const имяВкладки = узнатьИмяВкладки();

  /* Пока играющая вкладка жива, она обновляет отметку времени. Запись
     старше этого срока считается брошенной — например, вкладку закрыли. */
  const СРОК_ЗАНЯТОСТИ = 15 * 1000;
  const ОТМЕТКА_КАЖДЫЕ = 4 * 1000;

  function запомнитьКомнату(код, пропуск) {
    try {
      window.localStorage.setItem(КЛЮЧ_КОМНАТЫ, JSON.stringify({
        код: код, пропуск: пропуск, владелец: имяВкладки, отметка: Date.now()
      }));
    } catch (сбой) {
      /* запрещённая память — не повод ломать игру, просто не вернёмся после перезагрузки */
    }
    обновитьКнопкуВозврата();
  }

  function забытьКомнату() {
    // Чужую запись не стираем: за это время другая вкладка могла начать
    // свою игру, и её ключ возврата нам не принадлежит.
    if (комнатуДержитДругаяВкладка()) return;
    try {
      window.localStorage.removeItem(КЛЮЧ_КОМНАТЫ);
    } catch (сбой) {
      /* ничего страшного */
    }
    обновитьКнопкуВозврата();
  }

  /** Сохранённые код и пропуск или null, если их нет. */
  function вспомнитьКомнату() {
    let текст = null;
    try {
      текст = window.localStorage.getItem(КЛЮЧ_КОМНАТЫ);
    } catch (сбой) {
      return null;
    }
    if (!текст) return null;
    try {
      const разобранное = JSON.parse(текст);
      if (разобранное && разобранное.код && разобранное.пропуск) return разобранное;
    } catch (сбой) {
      /* испорченная запись — считаем, что её нет */
    }
    return null;
  }

  /**
   * Играет ли этой комнатой другая вкладка прямо сейчас. Отметка времени
   * свежая — значит там живой человек за столом, и лезть туда нельзя.
   */
  function комнатуДержитДругаяВкладка() {
    const запись = вспомнитьКомнату();
    if (!запись || !запись.владелец || запись.владелец === имяВкладки) return false;
    return Date.now() - (Number(запись.отметка) || 0) < СРОК_ЗАНЯТОСТИ;
  }

  /** Отметиться: «эта вкладка всё ещё за столом». */
  function отметитьВладение() {
    if (!код || !пропуск) return;
    const запись = вспомнитьКомнату();
    // Чужую запись не трогаем: вдруг за столом уже другая вкладка.
    if (запись && запись.код !== код) return;
    запомнитьКомнату(код, пропуск);
  }

  /* -------------------------------------------------------------------
     Состояние этой вкладки
     ------------------------------------------------------------------- */

  let код = null;              // код комнаты
  let пропуск = null;          // ключ возврата в свою партию
  let версия = 0;              // версия состояния, с которой мы спрашиваем новости
  let вПартии = false;         // идёт ли сейчас наша сетевая партия
  let опросИдёт = false;       // крутится ли длинный опрос
  let связьЕсть = true;        // отвечает ли сервер
  let попытокПодряд = 0;       // сколько раз подряд не достучались
  let последнееСостояние = null;
  let когдаБылоСобытие = 0;    // время последней новости — по нему видно раздумье
  let когдаОтвечалСервер = 0;  // время последнего удачного ответа
  let часовойСвязи = null;     // таймер, освежающий строку связи
  let часовойВладения = null;  // таймер, отмечающий «эта вкладка играет»
  let приветствиеДо = 0;       // до какого времени висит «друг пришёл»
  let ручкаОпроса = null;      // чем прервать висящий длинный опрос

  /* Номер попытки. Каждое новое начало (создали, вошли, вернулись, вышли)
     поднимает его на единицу. Ответ на старый запрос может прийти позже
     нового — например, на медленной связи, — и такой ответ нельзя
     применять: он выбросит человека из свежей комнаты обратно в старую,
     а друг останется за столом навсегда. Поэтому каждый ответ сверяет
     свой номер с текущим и, если отстал, молча выбрасывается. */
  let поколение = 0;

  function новоеПоколение() {
    поколение++;
    return поколение;
  }

  /** Не устарел ли ответ, пока летел. */
  function ответУстарел(моёПоколение) {
    return моёПоколение !== поколение;
  }

  /* -------------------------------------------------------------------
     Запросы к серверу
     ------------------------------------------------------------------- */

  /* Заголовок-пропуск через бесплатный туннель.

     Между игроком и домашним сервером стоит туннель — чужая программа,
     которая даёт домашнему компьютеру адрес в интернете. Некоторые
     бесплатные туннели (например, loca.lt) на запрос из браузера
     отвечают не сервером, а собственной страницей-предупреждением
     «дальше чужой туннель, точно хотите?». Человек её никогда не увидит:
     игра стучится в сервер сама, и вместо карт получает отказ 511 —
     то есть партия просто не начинается.

     Этот заголовок и есть просьба «страницу не показывай, пропусти
     к серверу». Всем остальным он безобиден: наш сервер и Cloudflare
     его просто не замечают. Поэтому шлём его всегда, не разбирая,
     по какому адресу идём.

     Важно: этот заголовок необычный, поэтому браузер сперва спрашивает
     у сервера разрешения отдельным запросом (OPTIONS). Разрешение выдаёт
     server/сервер.js — там заголовок назван в списке разрешённых. */
  const ПРОПУСК_ЧЕРЕЗ_ТУННЕЛЬ = { 'bypass-tunnel-reminder': 'true' };

  /**
   * Ответ пришёл, но не от нашего сервера. Такое бывает, когда туннель
   * умер посреди партии: до сервера запрос уже не доходит, и вместо ответа
   * возвращается страница посредника — «Bad Gateway», «Tunnel Unavailable»
   * или предупреждение самого туннеля.
   *
   * Узнаём это по одному верному признаку: наш сервер отвечает только
   * JSON, всегда и на любую беду. Не разобралось — значит отвечал не он.
   *
   * Почему это важно. Раньше такой ответ считался настоящим ответом
   * сервера. Человек нажимал на карту, ответ приходил без пояснений,
   * и игра делала худшее из возможного: объявляла, что связь в порядке,
   * писала «Друг на связи» — и молча не делала ход. Экран не менялся
   * вовсе, и понять, что происходит, было нельзя.
   */
  function отвечалНеСервер(номер) {
    return { ок: false, связьСорвалась: true, номер: номер, данные: {} };
  }

  /**
   * Один запрос. Никогда не «падает»: любая беда возвращается обычным
   * ответом с пометкой «связь сорвалась», чтобы её обработали в одном месте.
   */
  function запрос(путь, тело, сколькоЖдать, ручка) {
    const адрес = адресСервера();
    const управление = typeof AbortController !== 'undefined' ? new AbortController() : null;
    const сторож = setTimeout(function () {
      if (управление) управление.abort();
    }, сколькоЖдать || ОБЫЧНОЕ_ОЖИДАНИЕ);

    /* Через ручку запрос можно прервать снаружи. Это нужно при выходе
       в меню: висящий «что нового» вернулся бы в уже удалённую комнату
       и браузер написал бы в консоль красную ошибку 404. */
    if (ручка) {
      ручка.прервать = function () {
        clearTimeout(сторож);
        if (управление) управление.abort();
      };
    }

    const настройки = {
      method: 'POST',
      headers: Object.assign({ 'Content-Type': 'application/json' }, ПРОПУСК_ЧЕРЕЗ_ТУННЕЛЬ),
      body: JSON.stringify(тело || {})
    };
    if (управление) настройки.signal = управление.signal;

    return fetch(адрес + путь, настройки)
      .then(function (ответ) {
        return ответ.json().then(
          function (данные) {
            if (!данные || typeof данные !== 'object') return отвечалНеСервер(ответ.status);
            return { ок: ответ.ok, номер: ответ.status, данные: данные };
          },
          function () { return отвечалНеСервер(ответ.status); }
        );
      })
      .catch(function () {
        return { ок: false, связьСорвалась: true, данные: {} };
      })
      .then(function (итог) {
        clearTimeout(сторож);
        return итог;
      });
  }

  /** Запрос от имени игрока: код и пропуск подставляются сами. */
  function запросОтМеня(путь, тело, сколькоЖдать, ручка) {
    const полное = Object.assign({ код: код, пропуск: пропуск }, тело || {});
    return запрос(путь, полное, сколькоЖдать, ручка);
  }

  /* -------------------------------------------------------------------
     Экраны и надписи
     ------------------------------------------------------------------- */

  function узел(id) {
    return document.getElementById(id);
  }

  function написать(id, текст) {
    const место = узел(id);
    if (место) место.textContent = текст;
  }

  /** Показать или спрятать элемент. */
  function показать(id, видно) {
    const место = узел(id);
    if (место) место.classList.toggle('скрыт', !видно);
  }

  /** Сообщение на экране: пустой текст прячет строку целиком. */
  function сказать(id, текст) {
    написать(id, текст || '');
    показать(id, Boolean(текст));
  }

  /* ---------- Отклик прямо на кнопке ----------
     Без отклика человек не понимает, сработало ли нажатие. Особенно
     обидно, когда игра заранее знает ответ: она переписывала тот же текст
     в то же место, на экране не менялось ни пикселя, и кнопка выглядела
     сломанной. Поэтому теперь на каждое нажатие отвечает сама кнопка —
     это видно всегда, чем бы дело ни кончилось. */

  const ПОКАЗ_ОТВЕТА_КНОПКИ = 2000;   // сколько кнопка держит ответ вместо названия
  const памятьКнопок = {};            // id кнопки → её обычная надпись и таймер

  function памятьКнопки(кнопка) {
    const запись = памятьКнопок[кнопка.id] ||
                   (памятьКнопок[кнопка.id] = { надпись: '', таймер: null });
    // Обычную надпись берём из разметки при первом же обращении.
    if (!запись.надпись) запись.надпись = кнопка.textContent;
    return запись;
  }

  /** Ответить прямо на кнопке и через пару секунд вернуть ей название. */
  function ответитьНаКнопке(id, текст) {
    const кнопка = узел(id);
    if (!кнопка) return;
    const запись = памятьКнопки(кнопка);
    кнопка.textContent = текст;
    if (запись.таймер !== null) clearTimeout(запись.таймер);
    запись.таймер = setTimeout(function () {
      запись.таймер = null;
      кнопка.textContent = запись.надпись;
    }, ПОКАЗ_ОТВЕТА_КНОПКИ);
  }

  /**
   * Кнопка занята работой: надпись рассказывает, что происходит, а нажатия
   * больше не проходят. Это же и защита от двойного тапа — на телефоне
   * он случается сам собой.
   */
  function занятьКнопку(id, надпись) {
    const кнопка = узел(id);
    if (!кнопка) return;
    const запись = памятьКнопки(кнопка);
    if (запись.таймер !== null) {
      clearTimeout(запись.таймер);
      запись.таймер = null;
    }
    кнопка.textContent = надпись;
    кнопка.disabled = true;
  }

  /** Работа кончилась: вернуть кнопке название (или на пару секунд — ответ). */
  function освободитьКнопку(id, ответ) {
    const кнопка = узел(id);
    if (!кнопка) return;
    const запись = памятьКнопки(кнопка);
    кнопка.disabled = false;
    if (ответ) ответитьНаКнопке(id, ответ);
    else кнопка.textContent = запись.надпись;
  }

  /** Мост в js/game.js. Без него сетевой режим бесполезен. */
  function игра() {
    return window.ИграПоСети || null;
  }

  function показатьЭкран(id) {
    const мост = игра();
    if (мост && typeof мост.экран === 'function') мост.экран(id);
  }

  function показатьСвязь(текст, вид) {
    const мост = игра();
    if (мост && typeof мост.показатьСвязь === 'function') мост.показатьСвязь(текст, вид);
  }

  /* -------------------------------------------------------------------
     Строка связи: что происходит прямо сейчас
     ------------------------------------------------------------------- */

  /**
   * Одна строка над столом отвечает на два вопроса сразу: жив ли друг
   * и жива ли наша связь. Пишем словами, без значков — значок «!» человек
   * истолкует как угодно.
   */
  function освежитьСтрокуСвязи() {
    if (!вПартии) return;

    // Молчание дольше длинного опроса — тоже обрыв, даже если ни один
    // запрос ещё не успел сорваться: висящий запрос мог просто повиснуть.
    const давноМолчит = когдаОтвечалСервер > 0 &&
                        Date.now() - когдаОтвечалСервер > МОЛЧАНИЕ_ЭТО_ОБРЫВ;

    if (!связьЕсть || давноМолчит) {
      показатьСвязь('Связь с игрой потеряна. Пробуем восстановить…' +
                    (попытокПодряд > 0 ? ' (попытка ' + попытокПодряд + ')' : ''), 'тревога');
      return;
    }
    const вид = последнееСостояние;
    if (!вид) {
      показатьСвязь('Соединяемся с игрой…', 'ожидание');
      return;
    }
    if (вид.соперникУшёл) {
      показатьСвязь('Друг вышел из игры', 'тревога');
      return;
    }
    if (!вид.соперникНаСвязи) {
      показатьСвязь('Друг пропал со связи — ждём, партия сохранена', 'тревога');
      return;
    }
    // Первые секунды партии показываем сам факт: друг за столом.
    if (Date.now() < приветствиеДо) {
      показатьСвязь('Друг пришёл — играем!');
      return;
    }
    // Ходит друг и молчит уже долго: пусть будет видно, что игра не зависла.
    if (!вид.яХожу && !вид.завершена && Date.now() - когдаБылоСобытие > ДОЛГОЕ_РАЗДУМЬЕ) {
      показатьСвязь('Друг думает…', 'ожидание');
      return;
    }
    показатьСвязь('Друг на связи');
  }

  function запуститьЧасовогоСвязи() {
    if (часовойСвязи !== null) return;
    часовойСвязи = setInterval(освежитьСтрокуСвязи, ЧАСТОТА_СТРОКИ_СВЯЗИ);
  }

  function остановитьЧасовогоСвязи() {
    if (часовойСвязи === null) return;
    clearInterval(часовойСвязи);
    часовойСвязи = null;
  }

  /* -------------------------------------------------------------------
     Приём состояния от сервера
     ------------------------------------------------------------------- */

  /**
   * Принять новое состояние. Отсюда оно уходит в игру одной дверью —
   * так на экране всегда ровно то, что думает сервер.
   */
  function принятьСостояние(вид) {
    if (!вид) return;
    if (typeof вид.версия === 'number') версия = вид.версия;

    const прежнийНомер = последнееСостояние ? последнееСостояние.номерСобытия : -1;
    if (вид.номерСобытия !== прежнийНомер) когдаБылоСобытие = Date.now();
    последнееСостояние = вид;

    if (вид.этап === 'ожидание') {
      /* Сюда попадаем не только в начале. Бывает, что у друга оборвалась
         связь ровно на входе, и сервер откатил вход обратно: мы уже успели
         сесть за стол, а комната снова пуста. Тогда надо вернуть вкладку
         в то же состояние, в каком она была до прихода друга. Иначе его
         вторая попытка войти пройдёт мимо: «мы же уже в партии» — стол
         никто не покажет, и человек до конца просидит на «Ждём друга». */
      if (вПартии) {
        вПартии = false;
        приветствиеДо = 0;
        остановитьЧасовогоСвязи();
        показатьСвязь('');
      }
      показатьОжиданиеДруга(вид);
      return;
    }

    // Партия идёт (или уже доиграна, но комната жива — можно позвать на реванш).
    const мост = игра();
    if (!мост) return;
    if (!вПартии) {
      вПартии = true;
      мост.начать();
      запуститьЧасовогоСвязи();
      // Человек ждал не отчёта о скорости друга, а подтверждения, что тот
      // вообще пришёл. Сначала говорим это, а уже потом всё остальное.
      приветствиеДо = Date.now() + ПОКАЗ_ПРИВЕТСТВИЯ;
    }
    мост.показатьВид(вид);
    освежитьСтрокуСвязи();
  }

  /** Пока карты не розданы, показываем код и то, кто уже собрался за столом. */
  function показатьОжиданиеДруга(вид) {
    показатьКодКомнаты(вид.код || код || '');
    /* Список мест приходит только из комнаты на компанию. В обычной игре
       вдвоём его нет вовсе — там ждать нечего, кроме одного друга, и лишний
       список только мешал бы. */
    const компания = Array.isArray(вид.застолом);
    показать('прихожая', компания);
    if (компания) {
      нарисоватьПрихожую(вид);
    } else {
      написать('ожидание-соперника', 'Ждём, когда друг войдёт по коду…');
      сказать('сообщение-прихожей', '');
    }
    настроитьКнопкуОтмены(вид);
    показатьЭкран('экран-комнаты');
  }

  /* -------------------------------------------------------------------
     Прихожая: кто уже за столом и что можно нажать хозяину

     Прихожая — это несколько секунд перед раздачей карт, когда за столом
     собирается компания. Главный вопрос человека в эти секунды один:
     «все ли уже здесь». Поэтому список мест рисуется целиком — и занятые,
     и пустые, — а новости о приходе и уходе приносит длинный опрос, тот же
     самый, что потом носит ходы.
     ------------------------------------------------------------------- */

  /* Пока ответ на кнопку хозяина в пути, кнопки не трогаем: иначе пришедшая
     в эту секунду новость от опроса вернула бы им обычный вид, и человек
     решил бы, что нажатие не сработало. */
  let идётДействиеПрихожей = false;

  function нарисоватьПрихожую(вид) {
    написать('прихожая-правила', словаПроСтолКомнаты(вид));
    нарисоватьМеста(вид);
    // Стол собирает только хозяин, остальные ждут. Кнопок у них нет вовсе:
    // кнопка, которая всегда отвечает отказом, хуже её отсутствия.
    показать('кнопки-хозяина', вид.яХозяин === true);
    написать('ожидание-соперника', вид.яХозяин
      ? 'Скажите друзьям код. Все собрались — нажмите «Начать игру».'
      : 'Ждём, когда хозяин начнёт игру.');
    настроитьКнопкуНачать(вид);
  }

  /** Каким получился стол — по словам сервера, а не по нашему выбору. */
  function словаПроСтолКомнаты(вид) {
    const части = ['Играют ' + числоИгроков(Number(вид.мест) || МЕСТ_НА_ДВОИХ)];
    части.push(вид.парами ? 'парами, 2 на 2' : 'каждый сам за себя');
    if (вид.переводной) части.push('переводной');
    return части.join(', ') + '.';
  }

  /** Весь список мест заново: сначала занятые, потом свободные. */
  function нарисоватьМеста(вид) {
    const список = узел('список-мест');
    if (!список) return;
    список.innerHTML = '';

    const места = вид.застолом || [];
    for (const место of места) список.appendChild(строкаМеста(место));

    const всего = Number(вид.мест) || места.length;
    for (let пустое = места.length; пустое < всего; пустое++) {
      список.appendChild(строкаСвободногоМеста());
    }
  }

  /** Одна ячейка строки. Классы двойные: от таблицы рекордов — раскладка,
   *  свои — чтобы дизайнеру было за что взяться. */
  function ячейкаМеста(строка, классы, текст) {
    const ячейка = document.createElement('span');
    ячейка.className = классы;
    ячейка.textContent = текст;
    строка.appendChild(ячейка);
    return ячейка;
  }

  function строкаМеста(место) {
    const строка = document.createElement('div');
    строка.className = 'таблица__строка место-за-столом' +
                       (место.этоЯ ? ' место-за-столом--я' : '');
    ячейкаМеста(строка, 'таблица__место место-за-столом__номер', место.номер);
    ячейкаМеста(строка, 'таблица__очки место-за-столом__имя',
                место.имя + (место.этоЯ ? ' — вы' : ''));
    ячейкаМеста(строка, 'таблица__дата место-за-столом__роль', рольЗаСтолом(место));
    ячейкаМеста(строка, 'таблица__сложность место-за-столом__связь', какДелаУИгрока(место));
    return строка;
  }

  /** Кто это за столом: хозяин стола, бот или обычный игрок. */
  function рольЗаСтолом(место) {
    if (место.этоБот) return 'бот';
    return место.хозяин ? 'хозяин' : '';
  }

  /** Как дела у игрока — словами, без значков: их каждый толкует по-своему. */
  function какДелаУИгрока(место) {
    if (место.ушёл) return 'вышел';
    if (место.этоБот) return '';
    return место.наСвязи === false ? 'нет связи' : 'на связи';
  }

  function строкаСвободногоМеста() {
    const строка = document.createElement('div');
    строка.className = 'таблица__строка место-за-столом место-за-столом--пусто';
    ячейкаМеста(строка, 'таблица__место место-за-столом__номер', '·');
    ячейкаМеста(строка, 'таблица__очки место-за-столом__имя', 'Свободное место');
    ячейкаМеста(строка, 'таблица__дата место-за-столом__роль', '');
    ячейкаМеста(строка, 'таблица__сложность место-за-столом__связь', 'ждём');
    return строка;
  }

  /**
   * «Начать игру» не нажимается, пока за столом один человек: играть не с кем,
   * и сервер всё равно откажет. Пусть лучше кнопка честно молчит, чем отвечает
   * отказом на каждое нажатие.
   */
  function настроитьКнопкуНачать(вид) {
    const кнопка = узел('кнопка-начать-игру');
    if (!кнопка || идётДействиеПрихожей) return;
    кнопка.disabled = !вид.можноНачать;
  }

  /**
   * Внизу экрана одна кнопка значит разное: хозяин распускает стол, а гость
   * просто уходит из чужой комнаты. Надпись меняем прямо здесь и через
   * «занятьКнопку» эту кнопку не проводим — та запомнила бы первую надпись
   * и однажды вернула бы чужую.
   */
  function настроитьКнопкуОтмены(вид) {
    const кнопка = узел('кнопка-комната-отмена');
    if (!кнопка) return;
    кнопка.textContent = вид.яХозяин === false ? 'Выйти из комнаты' : 'Отменить игру';
  }

  /**
   * Нажатие на кнопку хозяина: посадить бота, убрать бота, начать игру.
   * Отказ сервера показываем словами как есть — он объясняет причину лучше
   * любой нашей догадки («Игра парами бывает только вчетвером, а за столом
   * трое»), и человеку нужно именно это.
   */
  function действиеПрихожей(действие, идКнопки, надписьНаВремя) {
    if (идётДействиеПрихожей) return;   // ответ на первое нажатие ещё в пути
    if (!код || !пропуск) {
      сказать('сообщение-прихожей', 'Комната уже закрыта — создайте игру заново.');
      return;
    }

    идётДействиеПрихожей = true;
    занятьКнопку(идКнопки, надписьНаВремя);
    сказать('сообщение-прихожей', '');

    const моё = поколение;
    запросОтМеня('/ход', { действие: действие }).then(function (ответ) {
      идётДействиеПрихожей = false;
      освободитьКнопку(идКнопки);
      if (ответУстарел(моё)) return;   // человек уже вышел из этой комнаты

      if (ответ.связьСорвалась) {
        связьПотеряна();
        сказать('сообщение-прихожей',
          'Связь с сервером пропала — попробуйте нажать ещё раз.');
        return;
      }
      if (ответ.номер === 404) {
        комнатаПропала();
        return;
      }
      if (!ответ.ок) {
        сказать('сообщение-прихожей',
          ответ.данные.ошибка || 'Сервер не принял это действие.');
        return;
      }
      if (!ответ.данные.принято) {
        сказать('сообщение-прихожей', ответ.данные.причина || 'Так сейчас нельзя.');
      }
      // Состояние применяем в любом случае: даже отказ приходит вместе
      // со свежим списком мест.
      if (ответ.данные.состояние) принятьСостояние(ответ.данные.состояние);
    });
  }

  /* Что стоит в плашке, пока код не пришёл. Точки помечаются отдельным
     классом: без пометки они выглядят как настоящее значение, и человек
     начинает диктовать другу четыре точки. */
  const ТОЧКИ_ВМЕСТО_КОДА = '····';

  function показатьКодКомнаты(значение) {
    const плашка = узел('код-комнаты');
    if (!плашка) return;
    const настоящий = /^[A-Z0-9]{4,}$/.test(значение || '');
    плашка.textContent = настоящий ? значение : ТОЧКИ_ВМЕСТО_КОДА;
    плашка.classList.toggle('код-игры--ждём', !настоящий);
  }

  /* -------------------------------------------------------------------
     Длинный опрос
     ------------------------------------------------------------------- */

  /** Сколько ждать перед следующей попыткой: чем дольше не выходит, тем реже стучимся. */
  function пауза() {
    const множитель = Math.pow(2, Math.max(0, попытокПодряд - 1));
    return Math.min(МАКСИМАЛЬНАЯ_ПАУЗА, ПАУЗА_ПОСЛЕ_СБОЯ * множитель);
  }

  function связьПотеряна() {
    попытокПодряд++;
    связьЕсть = false;
    освежитьСтрокуСвязи();
  }

  function связьВернулась() {
    попытокПодряд = 0;
    связьЕсть = true;
    когдаОтвечалСервер = Date.now();
    освежитьСтрокуСвязи();
  }

  /**
   * Комната пропала: сервер её уже не помнит (перезапустили, вышли оба,
   * прошло много времени). Играть дальше нечем — честно об этом говорим.
   */
  function комнатаПропала(причина) {
    остановитьОпрос();
    новоеПоколение();
    забытьКомнату();
    код = null;
    пропуск = null;
    последнееСостояние = null;
    const былиВПартии = вПартии;
    вПартии = false;
    приветствиеДо = 0;
    показатьСвязь('');
    остановитьЧасовогоСвязи();
    остановитьЧасовогоВладения();

    const мост = игра();
    if (былиВПартии && мост && typeof мост.вМеню === 'function') мост.вМеню();
    показатьЭкран('экран-друга');
    сказать('сообщение-друга', причина ||
      'Игра закрылась: сервер её больше не помнит. Создайте новую или войдите по коду.');
  }

  function остановитьОпрос() {
    опросИдёт = false;
    // Обрываем висящий запрос: без этого он вернётся в уже закрытую
    // комнату и оставит в консоли красную ошибку.
    if (ручкаОпроса && ручкаОпроса.прервать) ручкаОпроса.прервать();
    ручкаОпроса = null;
  }

  /**
   * Стук в дверь после обрыва. Спрашиваем коротко, «как дела сейчас»,
   * а не «что нового»: длинный опрос придержал бы ответ на полминуты,
   * и всё это время человек читал бы «связь потеряна», хотя она уже есть.
   */
  function достучаться() {
    const моё = поколение;
    запросОтМеня('/состояние', {}).then(function (ответ) {
      if (!опросИдёт || ответУстарел(моё)) return;
      if (ответ.номер === 404) {
        комнатаПропала();
        return;
      }
      if (ответ.связьСорвалась || !ответ.ок) {
        связьПотеряна();
        setTimeout(крутитьОпрос, пауза());
        return;
      }
      связьВернулась();
      if (ответ.данные.состояние) принятьСостояние(ответ.данные.состояние);
      крутитьОпрос();
    });
  }

  /** Спросить сервер о новостях и, что бы ни случилось, спросить снова. */
  function крутитьОпрос() {
    if (!опросИдёт || !код || !пропуск) return;
    if (!связьЕсть) {
      достучаться();
      return;
    }

    const моё = поколение;
    ручкаОпроса = { прервать: null };
    запросОтМеня('/что-нового', { версия: версия }, ОЖИДАНИЕ_ОПРОСА, ручкаОпроса)
      .then(function (ответ) {
      if (!опросИдёт || ответУстарел(моё)) return;

      if (ответ.связьСорвалась) {
        связьПотеряна();
        setTimeout(крутитьОпрос, пауза());
        return;
      }
      if (ответ.номер === 404) {
        комнатаПропала();
        return;
      }
      if (!ответ.ок) {
        // Сервер жив, но чем-то недоволен. Связь есть, поэтому просто
        // подождём и спросим снова — обычно это временная беда.
        связьПотеряна();
        setTimeout(крутитьОпрос, пауза());
        return;
      }

      связьВернулась();
      if (ответ.данные.комнатыНет) {
        комнатаПропала();
        return;
      }
      if (ответ.данные.изменилось && ответ.данные.состояние) {
        принятьСостояние(ответ.данные.состояние);
      }
      крутитьОпрос();
    });
  }

  function запуститьОпрос() {
    if (опросИдёт) return;
    опросИдёт = true;
    крутитьОпрос();
  }

  /* -------------------------------------------------------------------
     Создание игры, вход и возвращение
     ------------------------------------------------------------------- */

  /* Пробный стук в дверь: он нужен только чтобы отличить «там никого нет»
     от «там отвечает чужая программа». Долго ждать ради этого нельзя —
     человек и так уже прождал обычный запрос. */
  const ПРОБНОЕ_ОЖИДАНИЕ = 4000;

  /**
   * Кто сидит по адресу сервера. Обычный запрос игры браузер мог зарубить
   * сам: чужая программа не разрешает к себе обращаться со страницы игры,
   * и для нас это выглядит ровно как выключенный сервер. Поэтому стучимся
   * второй раз, но так, что ответ нам не нужен (режим no-cors): важно
   * только, ответил ли хоть кто-нибудь. Ответил — по адресу живёт чужая
   * программа, промолчал — там нет никого.
   */
  function ктоНаАдресе(адрес) {
    const управление = typeof AbortController !== 'undefined' ? new AbortController() : null;
    const сторож = setTimeout(function () {
      if (управление) управление.abort();
    }, ПРОБНОЕ_ОЖИДАНИЕ);
    /* Пропуска через туннель здесь нет нарочно: в режиме no-cors браузер
       необычные заголовки к запросу не добавляет вовсе — молча выбрасывает.
       И он тут не нужен: ответ мы всё равно не читаем, важен сам факт,
       что по адресу кто-то есть. */
    const настройки = { method: 'GET', mode: 'no-cors', cache: 'no-store' };
    if (управление) настройки.signal = управление.signal;
    return fetch((адрес || адресСервера()) + '/', настройки).then(
      function () { clearTimeout(сторож); return 'чужая'; },
      function () { clearTimeout(сторож); return 'никого'; }
    );
  }

  /* Приписка про то, где вписать адрес руками. Стоит в каждом объяснении
     первой строкой после самой беды: это единственный выход, который
     человек может пройти сам, не завися ни от бота, ни от чужой помощи. */
  const КАК_ВПИСАТЬ_АДРЕС =
    'Впишите адрес сервера сами: нажмите «Указать адрес сервера» ниже, ' +
    'вставьте адрес и нажмите «Проверить» — игра сразу скажет, отвечает он или нет.';

  /* Второй путь — свежая ссылка от бота. Он остался, но идёт вторым:
     бот бывает не запущен, и раньше этот совет заводил в тупик. */
  const КАК_ВЗЯТЬ_ССЫЛКУ =
    'Другой путь — свежая ссылка от бота: отправьте ему /start и нажмите ' +
    '«Играть» в новом сообщении (в старом сообщении адрес старый).';

  /** Человеческое объяснение, почему сервер молчит. */
  function почемуНеОтвечает(кто) {
    if (кто === 'чужая') {
      return 'По адресу ' + адресСервера() + ' отвечает не сервер игры, ' +
             'а какая-то другая программа — значит, адрес не тот, и запускать ' +
             'сервер бесполезно. ' + КАК_ВПИСАТЬ_АДРЕС + ' ' + КАК_ВЗЯТЬ_ССЫЛКУ;
    }
    return 'Сервер игры вдвоём не отвечает: по адресу ' + адресСервера() +
           ' сейчас никого нет. Часто причина простая: адрес туннеля меняется ' +
           'при каждом запуске, и старый адрес перестаёт работать. ' +
           КАК_ВПИСАТЬ_АДРЕС + ' ' + КАК_ВЗЯТЬ_ССЫЛКУ +
           ' А если игра запущена на своём компьютере — включите сервер игры вдвоём.';
  }

  /**
   * Сказать, почему сервер промолчал. Сначала коротко — чтобы нажатие сразу
   * получило ответ, — а через секунду-другую, когда пробный стук вернётся,
   * тем же местом объясняем точнее.
   */
  function рассказатьПочемуМолчит(кудаПисать, моё) {
    /* Выбранный адрес только что подвёл. Значит, прошлый итог спора устарел:
       забываем его, и следующее нажатие заново выяснит, кто из двух адресов
       живой. Так игра переезжает на вписанный адрес, даже если адрес из
       ссылки умер уже после того, как мы его выбрали. */
    забытьИтогСпора();
    сказать(кудаПисать, 'Сервер игры не ответил. Разбираемся, в чём дело…');
    // Кнопку «Указать адрес сервера» показываем сразу: что бы ни выяснил
    // пробный стук, вписать адрес руками поможет в любом случае.
    показатьВходВНастройку();
    ктоНаАдресе().then(function (кто) {
      if (ответУстарел(моё)) return;   // человек уже занялся другой игрой
      сказать(кудаПисать, почемуНеОтвечает(кто));
    });
  }

  /* -------------------------------------------------------------------
     Адрес сервера, вписанный руками

     Зачем это вообще есть. Адрес сервера обычно приезжает в самой ссылке
     на игру, и трогать его человеку незачем. Но если ссылка старая, а бот
     молчит, то без этого места игра вдвоём становится тупиком: все
     объяснения советуют взять свежую ссылку, а взять её негде. Поэтому
     здесь — единственный путь, который человек проходит сам.

     Почему спрятано. Обычному игроку про адреса знать не нужно, и лишняя
     кнопка на главном экране игры вдвоём только пугает. Вход появляется
     ровно тогда, когда беда уже случилась (или когда адрес однажды
     вписали — чтобы его можно было поправить или стереть).
     ------------------------------------------------------------------- */

  /* Части настройки, которые прячутся и показываются вместе. Сообщение
     о ходе дел живёт отдельно: оно появляется и исчезает по смыслу. */
  const ЧАСТИ_НАСТРОЙКИ = ['адрес-подпись', 'поле-адреса', 'кнопка-проверить-адрес',
                           'кнопка-сохранить-адрес'];

  let настройкаОткрыта = false;
  let входВНастройкуОткрыт = false;   // человек уже упёрся в беду — прятать нечего

  /** Показать кнопку «Указать адрес сервера»: дальше без неё не пройти. */
  function показатьВходВНастройку() {
    входВНастройкуОткрыт = true;
    обновитьВходВНастройку();
  }

  function обновитьВходВНастройку() {
    // Вписанный когда-то адрес — тоже повод показать вход: его надо уметь
    // поправить и стереть, не дожидаясь новой беды.
    const надо = входВНастройкуОткрыт || Boolean(сохранённыйАдрес() || вписанныйАдрес);
    показать('кнопка-адрес-сервера', надо);
    показать('кнопка-адрес-из-входа', надо);
  }

  /**
   * Слова о том, по какому адресу игра стучится и почему именно по нему.
   * Ни одного «вообще-то»: если адресов два, прямо сказано, какой из них
   * в ходу, какой отложен и по какой причине.
   */
  function словаПроАдрес(приставка) {
    const кто = кандидаты();
    const адрес = адресСервера();
    const откуда = откудаАдрес();
    let текст = (приставка ? приставка + ' ' : '') +
                'Сейчас игра стучится по адресу ' + адрес + '. ';

    if (откуда === 'ссылка') {
      текст += 'Этот адрес взят из самой ссылки на игру.';
      if (кто.вписан && кто.вписан !== адрес) {
        // Победа адреса из ссылки бывает двух сортов: он живой — или живых
        // нет вовсе. Путать их нельзя, иначе человек будет искать беду не там.
        if (итогГодится() && !итогСпора.ссылкаЖива && !итогСпора.вписанныйЖив) {
          текст += ' Вписанный вами адрес (' + кто.вписан + ') сейчас тоже молчит, ' +
                   'поэтому играть пока не по чему: проверьте адреса и запустите сервер.';
        } else {
          текст += ' Вписанный вами адрес (' + кто.вписан + ') отложен: адрес из ссылки ' +
                   'отвечает, а он главнее — иначе по свежей ссылке нельзя было бы ' +
                   'перейти на новый сервер. Ваш адрес вступит в дело, как только ' +
                   'адрес из ссылки перестанет отвечать.';
        }
      }
    } else if (откуда === 'вписан') {
      текст += 'Этот адрес вы вписали сами.';
      if (кто.ссылка && кто.ссылка !== адрес) {
        текст += ' В самой ссылке на игру записан другой адрес (' + кто.ссылка + '), ' +
                 'но он не отвечает — поэтому игра ходит по вашему.';
      }
    } else {
      текст += 'Это встроенный запасной адрес — он годится только тогда, когда ' +
               'сервер запущен на этом же компьютере.';
    }
    return текст;
  }

  /** Рассказать, по какому адресу игра стучится сейчас и откуда он взялся. */
  function рассказатьПроАдрес(приставка) {
    // Пока неизвестно, какой из двух адресов живой, сказать правду нечем:
    // сначала стучимся, потом рассказываем.
    if (естьСпор() && !итогГодится()) {
      сказать('сообщение-адреса', (приставка ? приставка + ' ' : '') +
        'В ссылке на игру записан один адрес сервера, а вами вписан другой. ' +
        'Проверяем, какой из них отвечает…');
      решитьСпорАдресов().then(function () {
        сказать('сообщение-адреса', словаПроАдрес(приставка));
      });
      return;
    }
    сказать('сообщение-адреса', словаПроАдрес(приставка));
  }

  function открытьНастройкуАдреса() {
    настройкаОткрыта = true;
    входВНастройкуОткрыт = true;
    ЧАСТИ_НАСТРОЙКИ.forEach(function (id) { показать(id, true); });
    показать('кнопка-стереть-адрес', Boolean(сохранённыйАдрес() || вписанныйАдрес));
    const поле = узел('поле-адреса');
    // Подставляем нынешний адрес: чаще всего его надо не сочинить заново,
    // а поправить одну букву.
    if (поле && !поле.value) поле.value = сохранённыйАдрес() || вписанныйАдрес || адресСервера();
    рассказатьПроАдрес();
    обновитьВходВНастройку();
  }

  function закрытьНастройкуАдреса() {
    настройкаОткрыта = false;
    ЧАСТИ_НАСТРОЙКИ.forEach(function (id) { показать(id, false); });
    показать('кнопка-стереть-адрес', false);
    сказать('сообщение-адреса', '');
  }

  /** Нажатие на «Указать адрес сервера»: открыть настройку или свернуть её. */
  function переключитьНастройкуАдреса() {
    if (настройкаОткрыта) закрытьНастройкуАдреса();
    else открытьНастройкуАдреса();
  }

  /** То же самое, но с экрана входа по коду: сначала вернуть человека туда,
   *  где живёт поле адреса. */
  function открытьНастройкуСЭкранаВхода() {
    сказать('сообщение-друга', '');
    показатьЭкран('экран-друга');
    if (!настройкаОткрыта) открытьНастройкуАдреса();
  }

  /* Сколько ждём ответа на проверку. Дольше обычного запроса не нужно:
     человек стоит и смотрит на кнопку. */
  const ПРОВЕРКА_АДРЕСА_ЖДЁТ = 6000;

  /* А столько ждём в споре двух адресов. Здесь человек ничего не нажимал
     и ждать не подряжался, поэтому срок короче: живой сервер отвечает
     на «здоровье» мгновенно, а от мёртвого мы всё равно ничего не дождёмся. */
  const СПОР_АДРЕСОВ_ЖДЁТ = 4000;

  /**
   * Стук в дверь сервера: жив ли он по этому адресу. Отвечаем одним словом:
   *   'сервер-игры' — там наш сервер, играть можно;
   *   'не-игра'     — кто-то ответил, но это не сервер игры;
   *   'отказ'       — сервер отвечает, но эту страницу игры не пускает;
   *   'молчит'      — до двери не достучались.
   */
  function стукВДверь(адрес, сколькоЖдать) {
    const управление = typeof AbortController !== 'undefined' ? new AbortController() : null;
    const сторож = setTimeout(function () {
      if (управление) управление.abort();
    }, сколькоЖдать || ПРОВЕРКА_АДРЕСА_ЖДЁТ);
    /* Пропуск через туннель нужен и здесь. Без него туннель отвечает
       своей страницей-предупреждением, игра считает живой сервер мёртвым
       и уводит человека чинить то, что и так работает. */
    const настройки = {
      method: 'GET', cache: 'no-store',
      headers: Object.assign({}, ПРОПУСК_ЧЕРЕЗ_ТУННЕЛЬ)
    };
    if (управление) настройки.signal = управление.signal;

    return fetch(адрес + '/здоровье', настройки).then(function (ответ) {
      clearTimeout(сторож);
      if (!ответ.ok) return { итог: 'отказ', номер: ответ.status };
      return ответ.json().then(
        function (данные) {
          return { итог: данные && данные.живой ? 'сервер-игры' : 'не-игра' };
        },
        function () { return { итог: 'не-игра' }; }
      );
    }, function () {
      clearTimeout(сторож);
      return { итог: 'молчит' };
    });
  }

  /**
   * Отвечает ли по адресу именно наш сервер игры. Нужно для спора двух
   * адресов, поэтому ответ короткий — да или нет. Всё, кроме нашего живого
   * сервера, считаем «нет»: по чужой программе и по отказу играть нельзя
   * ровно так же, как по пустому месту.
   */
  function отвечаетЛиАдрес(адрес) {
    // Незащищённый адрес с защищённой страницы браузер не пропустит —
    // стучаться туда бессмысленно, только время терять.
    if (!адрес || браузерЗапретит(адрес)) return Promise.resolve(false);
    return стукВДверь(адрес, СПОР_АДРЕСОВ_ЖДЁТ).then(function (ответ) {
      return ответ.итог === 'сервер-игры';
    });
  }

  /**
   * То же самое, но для кнопки «Проверить»: человеку важно отличить чужую
   * программу от пустого места, поэтому в тишину стучимся второй раз —
   * ответ чужой программы браузер прячет от нас так же, как её отсутствие.
   */
  function постучатьсяВСервер(адрес) {
    return стукВДверь(адрес).then(function (ответ) {
      if (ответ.итог !== 'молчит') return ответ;
      return ктоНаАдресе(адрес).then(function (кто) {
        return { итог: кто === 'чужая' ? 'чужая' : 'молчит' };
      });
    });
  }

  let идётПроверкаАдреса = false;

  /**
   * Проверить адрес, который сейчас в поле, и честно сказать, что там.
   * Нужна до того, как человек начнёт создавать игру: иначе он узнает
   * о беде уже с кодом на руках и другом на проводе.
   */
  function проверитьАдресСервера(чьяКнопка) {
    if (идётПроверкаАдреса) return;
    const поле = узел('поле-адреса');
    const разбор = привестиАдрес(поле ? поле.value : '');
    if (!разбор.адрес) {
      ответитьНаКнопке(чьяКнопка, 'Адрес не понят');
      сказать('сообщение-адреса', разбор.беда);
      return;
    }
    if (поле) поле.value = разбор.адрес;   // показываем, что именно проверяем
    if (браузерЗапретит(разбор.адрес)) {
      ответитьНаКнопке(чьяКнопка, 'Так не выйдет');
      сказать('сообщение-адреса',
        'Такой адрес отсюда не сработает: он начинается с http://, а игра, открытая ' +
        'по этой ссылке, может стучаться только по адресам на https://. ' +
        'Впишите адрес туннеля — он выглядит так: https://имя-сервера.trycloudflare.com.');
      return;
    }

    идётПроверкаАдреса = true;
    занятьКнопку(чьяКнопка, 'Проверяем…');
    постучатьсяВСервер(разбор.адрес).then(function (ответ) {
      идётПроверкаАдреса = false;
      освободитьКнопку(чьяКнопка);
      const итог = чтоТамПоАдресу(ответ, разбор.адрес);
      сказать('сообщение-адреса', итог);
      /* Адресов два — тогда «отвечает ли этот» ещё не весь ответ: человеку
         надо знать, по какому из двух пойдёт игра. Дописываем это второй
         фразой, когда спор будет решён. */
      if (естьСпор()) {
        решитьСпорАдресов().then(function () {
          сказать('сообщение-адреса', итог + ' ' + словаПроАдрес());
        });
      }
    });
  }

  /** Слова для итога проверки — так, чтобы было понятно, что делать дальше. */
  function чтоТамПоАдресу(ответ, адрес) {
    if (ответ.итог === 'сервер-игры') {
      const свой = (сохранённыйАдрес() || вписанныйАдрес) === адрес;
      return 'Сервер игры отвечает — по этому адресу можно играть. ' +
             (свой ? 'Нажмите «Назад» и создавайте игру.'
                   : 'Нажмите «Сохранить адрес», чтобы игра его запомнила.');
    }
    if (ответ.итог === 'отказ') {
      return 'По адресу ' + адрес + ' сервер отвечает, но эту страницу игры не пускает ' +
             '(ответ ' + ответ.номер + '). Скорее всего, сервер настроен на другой сайт — ' +
             'спросите адрес у того, кто его запускал.';
    }
    if (ответ.итог === 'не-игра') {
      return 'По адресу ' + адрес + ' кто-то отвечает, но это не сервер игры. ' +
             'Проверьте адрес — возможно, он устарел.';
    }
    if (ответ.итог === 'чужая') {
      return 'По адресу ' + адрес + ' отвечает другая программа, а не сервер игры. ' +
             'Значит, адрес не тот.';
    }
    return 'По адресу ' + адрес + ' никто не отвечает. Если сервер запущен на своём ' +
           'компьютере — включите его. Если это туннель — его адрес мог смениться, ' +
           'возьмите свежий у того, кто запускал сервер.';
  }

  /** Запомнить вписанный адрес и тут же проверить, отвечает ли он. */
  function сохранитьАдресСервера() {
    const поле = узел('поле-адреса');
    const разбор = привестиАдрес(поле ? поле.value : '');
    if (!разбор.адрес) {
      ответитьНаКнопке('кнопка-сохранить-адрес', 'Адрес не понят');
      сказать('сообщение-адреса', разбор.беда);
      return;
    }
    if (поле) поле.value = разбор.адрес;   // показываем, что именно запомнили
    const легло = запомнитьАдрес(разбор.адрес);
    забытьИтогСпора();   // адрес поменялся — прошлый победитель уже не в счёт
    показать('кнопка-стереть-адрес', true);
    обновитьВходВНастройку();
    ответитьНаКнопке('кнопка-сохранить-адрес', легло ? 'Адрес сохранён' : 'Адрес принят');

    const начало = легло
      ? 'Адрес сохранён: ' + разбор.адрес + '. Браузер его помнит — вписывать заново не нужно.'
      : 'Адрес принят: ' + разбор.адрес + '. Запомнить его не вышло — браузер не дал ' +
        'доступ к своей памяти, поэтому после перезагрузки страницы впишите адрес снова.';

    /* В ссылке записан другой адрес — значит, спор, и решает его не наше
       желание, а то, кто из двух отвечает. Раньше на этом месте человеку
       говорили «играть всё равно будем по адресу из ссылки», и на мёртвой
       ссылке это был тупик: вписывать адрес было бессмысленно. */
    if (естьСпор()) {
      сказать('сообщение-адреса', начало +
        ' В ссылке на игру записан другой адрес — проверяем, какой из двух отвечает…');
      решитьСпорАдресов().then(function () {
        сказать('сообщение-адреса', словаПроАдрес(начало));
      });
      return;
    }
    сказать('сообщение-адреса', начало + ' Проверяем, отвечает ли он…');
    проверитьАдресСервера('кнопка-проверить-адрес');
  }

  /** Стереть вписанный адрес и вернуться к тому, что в ссылке. */
  function стеретьАдресСервера() {
    забытьАдрес();
    забытьИтогСпора();   // спорить больше не о чем: адрес остался один
    const поле = узел('поле-адреса');
    if (поле) поле.value = адресСервера();
    показать('кнопка-стереть-адрес', false);
    обновитьВходВНастройку();
    рассказатьПроАдрес('Вписанный адрес стёрт.');
  }

  /* -------------------------------------------------------------------
     Кто садится за стол: имя игрока и каким будет стол
     ------------------------------------------------------------------- */

  /**
   * Как звать игрока за столом. Имя берём у Telegram — оно там уже есть,
   * и спрашивать человека незачем. Имени нет (игра открыта в обычном
   * браузере) — ничего не выдумываем: сервер сам назовёт «Игрок 2» по номеру
   * места.
   *
   * Почему имя добывается здесь, а не в js/telegram.js: тот файл отдаёт
   * наружу ровно три функции про рекорды, имени среди них нет. Поэтому
   * спрашиваем Telegram сами и очень осторожно — любая беда молча
   * превращается в «имени нет», и игра идёт дальше.
   */
  function имяИгрока() {
    try {
      const приложение = window.Telegram && window.Telegram.WebApp;
      const кто = приложение && приложение.initDataUnsafe && приложение.initDataUnsafe.user;
      if (!кто) return '';
      return String(кто.first_name || кто.username || '').trim();
    } catch (сбой) {
      return '';
    }
  }

  /* Каким будет стол. Пока человек ничего не трогал, здесь стоит обычная
     игра вдвоём — ровно та, что была в игре с другом всегда. */
  const МЕСТ_НА_ДВОИХ = 2;
  const САМЫЙ_БОЛЬШОЙ_СТОЛ = 6;
  const ИГРОКОВ_В_ПАРАХ = 4;      // парная игра бывает только вчетвером

  const выборСтола = { мест: МЕСТ_НА_ДВОИХ, переводной: false, парами: false };

  /** Человек ничего не менял — значит, это прежняя игра вдвоём. */
  function столОбычный() {
    return выборСтола.мест === МЕСТ_НА_ДВОИХ &&
           !выборСтола.переводной && !выборСтола.парами;
  }

  /* Числа словами: «играют трое» читается легче, чем «играют 3». */
  const ЧИСЛО_СЛОВАМИ = { 2: 'двое', 3: 'трое', 4: 'четверо', 5: 'пятеро', 6: 'шестеро' };

  function числоИгроков(сколько) {
    return ЧИСЛО_СЛОВАМИ[сколько] || (сколько + ' игроков');
  }

  /**
   * Что уходит серверу в запросе «создать».
   *
   * Настройки стола шлём только тогда, когда человек их менял: комната
   * с настройками — это комната на компанию, с прихожей и кнопкой «Начать».
   * Ничего не трогал — уходит одно имя, и получается прежняя комната
   * на двоих, где карты раздаются сами, как только войдёт друг. Одно имя
   * настройкой не считается, поэтому старая игра вдвоём не меняется.
   */
  function телоСоздания() {
    const тело = {};
    const имя = имяИгрока();
    if (имя) тело.имя = имя;
    if (столОбычный()) return тело;
    тело.мест = выборСтола.мест;
    тело.переводной = выборСтола.переводной;
    тело.парами = выборСтола.парами;
    return тело;
  }

  /** Отметить нажатую кнопку в ряду выбора и погасить остальные. */
  function отметитьВыбор(идБлока, значение) {
    const блок = узел(идБлока);
    if (!блок) return;
    for (const кнопка of блок.querySelectorAll('.кнопка--выбор')) {
      кнопка.classList.toggle('кнопка--активная', кнопка.value === значение);
    }
  }

  /** Показать выбранное на кнопках и объяснить словами, что получится. */
  function показатьВыборСтола() {
    отметитьВыбор('выбор-мест', String(выборСтола.мест));
    отметитьВыбор('выбор-перевода', выборСтола.переводной ? 'переводной' : 'обычный');
    отметитьВыбор('выбор-пар', выборСтола.парами ? 'парами' : 'каждый');
    написать('пояснение-стола', словаПроВыборСтола());
  }

  /**
   * Что получится при нынешнем выборе — обычными словами, без терминов.
   *
   * Пояснение живёт в отведённом ему месте в четыре строки, поэтому каждая
   * фраза здесь короткая нарочно: длинный текст выталкивал вёрстку вниз.
   * По той же причине пропала фраза «парами играют только вчетвером» —
   * она показывалась ровно тогда, когда человек уже нажал «парами»
   * и число мест на его глазах стало четыре.
   */
  function словаПроВыборСтола() {
    if (столОбычный()) {
      return 'Обычная игра вдвоём: карты раздадутся сами, как только друг войдёт по коду.';
    }
    let текст = 'Играют ' + числоИгроков(выборСтола.мест) + '. ';
    текст += выборСтола.парами
      ? 'Парами: двое против двоих, напарник напротив. '
      : 'Каждый сам за себя. ';
    if (выборСтола.переводной) {
      текст += 'Переводной: положите такую же карту — и отбивается сосед. ';
    }
    return текст + 'Свободные места можно занять ботами. Игру начнёте вы — кнопкой.';
  }

  /**
   * Выбрать, сколько человек за столом. Игра парами бывает только вчетвером,
   * поэтому вместе с другим числом мест она выключается сама — и об этом
   * сказано сразу, а не отказом в последнюю минуту, когда все уже собрались.
   */
  function выбратьМеста(сколько) {
    const число = Number(сколько);
    if (!(число >= МЕСТ_НА_ДВОИХ && число <= САМЫЙ_БОЛЬШОЙ_СТОЛ)) return;
    выборСтола.мест = число;
    if (выборСтола.парами && число !== ИГРОКОВ_В_ПАРАХ) выборСтола.парами = false;
    показатьВыборСтола();
  }

  /**
   * Включить или выключить игру парами. Включили при другом числе мест —
   * сами ставим четыре: человек выбирал игру, а не число мест, и упираться
   * тут не во что.
   */
  function выбратьПары(парами) {
    выборСтола.парами = парами;
    if (парами) выборСтола.мест = ИГРОКОВ_В_ПАРАХ;
    показатьВыборСтола();
  }

  /** Повесить одно действие на все кнопки одного ряда выбора. */
  function накнопкиВыбора(идБлока, действие) {
    const блок = узел(идБлока);
    if (!блок) {
      console.warn('Игра вдвоём: не нашёл выбор «' + идБлока + '». ' +
                   'Скорее всего, браузер показывает старую страницу — обновите её (Ctrl+F5).');
      return;
    }
    for (const кнопка of блок.querySelectorAll('.кнопка--выбор')) {
      кнопка.addEventListener('click', function () { действие(кнопка.value); });
    }
  }

  function подключитьВыборСтола() {
    накнопкиВыбора('выбор-мест', выбратьМеста);
    накнопкиВыбора('выбор-перевода', function (значение) {
      выборСтола.переводной = (значение === 'переводной');
      показатьВыборСтола();
    });
    накнопкиВыбора('выбор-пар', function (значение) {
      выбратьПары(значение === 'парами');
    });
    показатьВыборСтола();
  }

  /* Пока ответ на «создать» или «войти» не пришёл, второй такой же запрос
     не отправляем: двойной тап на телефоне — обычное дело, а на сервере
     от него оставались две комнаты, и первая висела мусором. */
  let создаёмИгру = false;
  let входимВИгру = false;

  /* Нажали «Создать игру». Если адреса два и неизвестно, какой из них
     живой, сперва выясняем это: иначе игра создалась бы не на том сервере,
     а друг вошёл бы в пустоту. */
  function создатьИгру() {
    приВыбранномАдресе('кнопка-создать-игру', создатьИгруНаСервере);
  }

  function создатьИгруНаСервере() {
    if (создаёмИгру) return;          // ответ на первое нажатие ещё в пути

    const беда = почемуАдресНеПодходит(адресСервера());
    if (беда) {
      // Объяснение показываем именно здесь, по нажатию. Раньше оно висело
      // на экране заранее, и от нажатия не менялось ничего — человек видел
      // сломанную кнопку и не знал, чего ждать.
      ответитьНаКнопке('кнопка-создать-игру', 'Не выходит — читайте ниже');
      сказать('сообщение-друга', беда);
      показатьВходВНастройку();   // в объяснении сказано «нажмите ниже» — покажем эту кнопку
      return;
    }

    создаёмИгру = true;
    занятьКнопку('кнопка-создать-игру', 'Создаём игру…');
    сказать('сообщение-друга', '');
    // Старый код с прошлой игры показывать нельзя: его уже никто не ждёт.
    показатьКодКомнаты('');
    сказать('сообщение-копирования', '');
    // Список из прошлой комнаты тоже чужой: его соберём заново по ответу.
    показать('прихожая', false);
    сказать('сообщение-прихожей', '');

    const моё = новоеПоколение();
    запрос('/создать', телоСоздания()).then(function (ответ) {
      создаёмИгру = false;
      освободитьКнопку('кнопка-создать-игру');
      if (ответУстарел(моё)) return;   // человек уже ушёл в другую игру
      if (ответ.связьСорвалась) {
        рассказатьПочемуМолчит('сообщение-друга', моё);
        return;
      }
      if (!ответ.ок || !ответ.данные.код) {
        сказать('сообщение-друга', ответ.данные.ошибка || 'Сервер не смог создать игру.');
        return;
      }
      сказать('сообщение-друга', '');
      начатьЖизньВКомнате(ответ.данные.код, ответ.данные.пропуск, ответ.данные.состояние);
    });
  }

  /** Привести набранный код к виду, который понимает сервер. */
  function очиститьКод(что) {
    return String(что || '').toUpperCase().replace(/[^A-Z0-9]/g, '').slice(0, 6);
  }

  /* То же и на входе по коду: сначала адрес, потом стук в сервер. */
  function войтиПоКоду() {
    приВыбранномАдресе('кнопка-войти', войтиПоКодуНаСервере);
  }

  function войтиПоКодуНаСервере() {
    if (входимВИгру) return;          // ответ на первое нажатие ещё в пути

    const беда = почемуАдресНеПодходит(адресСервера());
    if (беда) {
      ответитьНаКнопке('кнопка-войти', 'Не выходит — читайте ниже');
      сказать('сообщение-входа', беда);
      показатьВходВНастройку();
      return;
    }
    const поле = узел('поле-кода');
    const набранный = очиститьКод(поле ? поле.value : '');
    if (набранный.length < 4) {
      ответитьНаКнопке('кнопка-войти', 'Кода не хватает');
      сказать('сообщение-входа', 'Код состоит из четырёх знаков — наберите его целиком.');
      return;
    }

    входимВИгру = true;
    занятьКнопку('кнопка-войти', 'Входим в игру…');
    сказать('сообщение-входа', '');

    const моё = новоеПоколение();
    // Имя нужно, чтобы за столом было видно, кто пришёл. Не назвались —
    // сервер сам даст имя по номеру места.
    const телоВхода = { код: набранный };
    const имя = имяИгрока();
    if (имя) телоВхода.имя = имя;

    запрос('/войти', телоВхода).then(function (ответ) {
      входимВИгру = false;
      освободитьКнопку('кнопка-войти');
      if (ответУстарел(моё)) return;
      if (ответ.связьСорвалась) {
        рассказатьПочемуМолчит('сообщение-входа', моё);
        return;
      }
      if (!ответ.ок || !ответ.данные.пропуск) {
        сказать('сообщение-входа', ответ.данные.ошибка ||
          'Войти не получилось. Проверьте код — возможно, игру уже начали без вас.');
        return;
      }
      сказать('сообщение-входа', '');
      начатьЖизньВКомнате(ответ.данные.код || набранный, ответ.данные.пропуск,
                          ответ.данные.состояние);
    });
  }

  /** Мы в комнате: запоминаем ключи, показываем первое состояние и слушаем новости. */
  function начатьЖизньВКомнате(новыйКод, новыйПропуск, состояние) {
    остановитьОпрос();          // старый опрос мог ещё висеть на прошлой комнате
    новоеПоколение();           // всё, что летело раньше, теперь устарело
    код = новыйКод;
    пропуск = новыйПропуск;
    версия = 0;
    попытокПодряд = 0;
    связьЕсть = true;
    последнееСостояние = null;
    когдаБылоСобытие = Date.now();
    когдаОтвечалСервер = Date.now();
    приветствиеДо = 0;
    запомнитьКомнату(код, пропуск);
    запуститьЧасовогоВладения();
    if (состояние) принятьСостояние(состояние);
    else показатьЭкран('экран-комнаты');
    запуститьОпрос();
  }

  /* Пока эта вкладка за столом, она регулярно отмечается в памяти
     браузера. По этой отметке вторая вкладка понимает, что место занято. */
  function запуститьЧасовогоВладения() {
    if (часовойВладения !== null) return;
    часовойВладения = setInterval(отметитьВладение, ОТМЕТКА_КАЖДЫЕ);
  }

  function остановитьЧасовогоВладения() {
    if (часовойВладения === null) return;
    clearInterval(часовойВладения);
    часовойВладения = null;
  }

  /**
   * Кончилась ли игра в этой комнате совсем. Партия доиграна — этого мало:
   * пока друг за столом, он может позвать на реванш, и вернуться туда стоит.
   * А вот доигранная партия, из которой друг уже ушёл (или пропал со связи), —
   * мёртвая комната: в ней нечего делать ни нам, ни ему.
   */
  function играВКомнатеКончилась(вид) {
    if (!вид) return false;
    if (!вид.завершена && вид.этап !== 'конец') return false;
    return Boolean(вид.соперникУшёл) || !вид.соперникНаСвязи;
  }

  /**
   * Вернуться в партию, начатую до перезагрузки страницы. Спрашиваем сервер,
   * жива ли комната: если нет — молча забываем ключи, чтобы не предлагать
   * человеку вернуться в никуда.
   */
  function попробоватьВернуться(сСообщением) {
    const сохранённое = вспомнитьКомнату();
    if (!сохранённое) return;
    if (почемуАдресНеПодходит(адресСервера())) return;

    // За этим столом уже сидит другая вкладка. Сесть туда же нельзя:
    // выход из второй вкладки выбросил бы из партии и первую.
    if (комнатуДержитДругаяВкладка()) {
      сказать('сообщение-друга', 'Эта игра уже открыта в другой вкладке — играйте там. ' +
        'Здесь можно создать новую игру или войти к другому другу.');
      return;
    }

    if (сСообщением) сказать('сообщение-друга', 'Возвращаемся в вашу игру…');

    /* Ключи от комнаты нарочно не кладём в «код» и «пропуск», пока сервер
       не подтвердил, что партия жива, — спрашиваем о ней напрямую. Раньше
       мы занимали место сразу, и выход, нажатый в эти секунды ожидания,
       уходил на сервер по-настоящему: человек всего лишь передумал
       возвращаться, а партия рвалась у обоих. */
    const моё = новоеПоколение();
    запрос('/состояние', { код: сохранённое.код, пропуск: сохранённое.пропуск })
        .then(function (ответ) {
      // Пока ответ шёл, человек мог войти в другую игру. Такой ответ
      // применять нельзя: он выкинет его обратно в старую комнату,
      // а друг останется за столом один и навсегда.
      if (ответУстарел(моё)) return;
      if (ответ.связьСорвалась) {
        if (сСообщением) рассказатьПочемуМолчит('сообщение-друга', моё);
        return;
      }
      if (!ответ.ок || !ответ.данные.состояние) {
        // Комнаты нет — ключи бесполезны. За столом мы так и не сели,
        // поэтому чистить нечего, кроме памяти браузера.
        забытьКомнату();
        if (сСообщением) сказать('сообщение-друга', 'Прошлая игра уже закрыта. Создайте новую.');
        return;
      }
      /* Комната жива, но играть в ней уже нечего. Возвращаться туда нельзя:
         человек увидел бы экран доигранной партии с единственной кнопкой
         «В меню» и решил бы, что игра застряла. Вместо этого выбрасываем
         ключи и оставляем его там, откуда начинают новую игру. */
      if (играВКомнатеКончилась(ответ.данные.состояние)) {
        забытьКомнату();
        if (сСообщением) {
          сказать('сообщение-друга', 'Прошлая игра с другом уже доиграна, и за столом ' +
            'никого не осталось. Создайте новую игру или войдите по коду.');
        }
        return;
      }
      if (сСообщением) сказать('сообщение-друга', '');
      начатьЖизньВКомнате(сохранённое.код, сохранённое.пропуск, ответ.данные.состояние);
    });
  }

  /* -------------------------------------------------------------------
     Уход из партии
     ------------------------------------------------------------------- */

  /**
   * Выйти из партии: сказать серверу (чтобы друг сразу увидел уход),
   * погасить опрос и забыть ключи. Вызывать можно всегда — если сетевой
   * партии нет, ничего не произойдёт.
   */
  function покинутьПартию() {
    остановитьОпрос();
    остановитьЧасовогоСвязи();
    остановитьЧасовогоВладения();
    новоеПоколение();       // всё, что ещё летит, к этой партии уже не относится
    показатьСвязь('');
    вПартии = false;
    последнееСостояние = null;
    приветствиеДо = 0;
    if (!код || !пропуск) return;
    const уходящийКод = код;
    const уходящийПропуск = пропуск;
    код = null;
    пропуск = null;
    забытьКомнату();
    // Ответ нам уже не нужен: мы уходим в любом случае.
    запрос('/выйти', { код: уходящийКод, пропуск: уходящийПропуск });
  }

  /* -------------------------------------------------------------------
     Кнопки
     ------------------------------------------------------------------- */

  /**
   * Показать в меню кнопку возврата, если есть недоигранная партия.
   * Живость комнаты здесь не проверяем: лишний запрос при каждом открытии
   * меню того не стоит, а если игра уже закрыта, человеку об этом скажут
   * сразу после нажатия.
   */
  function обновитьКнопкуВозврата() {
    const кнопка = узел('кнопка-вернуться-в-игру');
    if (!кнопка) return;
    const естьЧтоПродолжить = Boolean(вспомнитьКомнату()) && !комнатуДержитДругаяВкладка();
    кнопка.classList.toggle('скрыт', !естьЧтоПродолжить);
  }

  function открытьЭкранДруга() {
    сказать('сообщение-друга', '');
    показатьЭкран('экран-друга');
    обновитьВходВНастройку();
    /* Адрес проверяем и здесь, но объяснение заранее НЕ показываем. Раньше
       оно встречало человека прямо на входе, и тогда нажатие «Создать игру»
       ничего на экране не меняло: тот же текст перерисовывался сам в себя.
       Кнопка выглядела сломанной. Теперь беда всплывает по нажатию — вместе
       с ответом на самой кнопке. Здесь же остаётся только одно: не пытаться
       вернуться в прошлую партию, если сервер всё равно недостижим.

       Спор двух адресов запускаем прямо тут, в фоне и без всяких надписей:
       человек как раз читает экран и решает, создавать игру или входить по
       коду, — к его нажатию ответ обычно уже готов, и ждать не придётся. */
    приВыбранномАдресе(null, function () {
      if (почемуАдресНеПодходит(адресСервера())) return;
      // Есть недоигранная партия — попробуем вернуться в неё сами.
      if (вспомнитьКомнату()) попробоватьВернуться(true);
    });
  }

  /* -------------------------------------------------------------------
     Копирование кода
     ------------------------------------------------------------------- */

  /**
   * Старый способ копирования — через невидимое поле. Нужен там, где нового
   * буфера обмена нет: он работает только на защищённых страницах, а внутри
   * Telegram встроенный браузер иногда не даёт и его.
   */
  function скопироватьЧерезПоле(текст) {
    try {
      const поле = document.createElement('textarea');
      поле.value = текст;
      поле.setAttribute('readonly', '');
      поле.style.position = 'fixed';
      поле.style.top = '-1000px';
      document.body.appendChild(поле);
      поле.select();
      // Без этой строки на iPhone выделение не срабатывает.
      if (поле.setSelectionRange) поле.setSelectionRange(0, текст.length);
      const вышло = document.execCommand && document.execCommand('copy');
      document.body.removeChild(поле);
      return Boolean(вышло);
    } catch (сбой) {
      return false;
    }
  }

  /** Положить текст в буфер обмена. Сначала новым способом, потом старым. */
  function положитьВБуфер(текст) {
    const буфер = window.navigator && window.navigator.clipboard;
    if (буфер && typeof буфер.writeText === 'function') {
      try {
        return буфер.writeText(текст).then(
          function () { return true; },
          function () { return скопироватьЧерезПоле(текст); }
        );
      } catch (сбой) {
        return Promise.resolve(скопироватьЧерезПоле(текст));
      }
    }
    return Promise.resolve(скопироватьЧерезПоле(текст));
  }

  function скопироватьКод() {
    if (!код) {
      сказать('сообщение-копирования', 'Код ещё не пришёл — подождите секунду.');
      return;
    }
    положитьВБуфер(код).then(function (вышло) {
      if (вышло) {
        ответитьНаКнопке('кнопка-копировать-код', 'Код скопирован');
        сказать('сообщение-копирования', 'Код в буфере — вставьте его другу в переписку.');
        return;
      }
      // Молчать нельзя: человек решит, что скопировалось, и отправит пустоту.
      ответитьНаКнопке('кнопка-копировать-код', 'Скопировать не вышло');
      сказать('сообщение-копирования',
        'Скопировать не получилось — телефон не дал доступ к буферу обмена. ' +
        'Продиктуйте другу код: ' + код);
    });
  }

  function открытьЭкранВхода() {
    сказать('сообщение-входа', '');
    const поле = узел('поле-кода');
    if (поле) поле.value = '';
    показатьЭкран('экран-входа');
    if (поле) поле.focus();
  }

  function отменитьКомнату() {
    покинутьПартию();
    сказать('сообщение-друга', '');
    сказать('сообщение-копирования', '');
    показатьКодКомнаты('');   // чужой старый код в плашке никому не нужен
    // И список тех, кто сидел за покинутым столом, тоже убираем.
    показать('прихожая', false);
    сказать('сообщение-прихожей', '');
    показатьЭкран('экран-друга');
  }

  /**
   * Бросить начатую попытку вернуться в партию. Серверу мы при этом ничего
   * не говорим и ключи возврата не стираем: партия жива, друг за столом,
   * вернуться можно в любой момент. Единственное, что делаем, — помечаем
   * улетевший вопрос о комнате устаревшим, иначе его ответ через секунду
   * затащил бы человека за стол прямо из меню.
   */
  function отменитьВозврат() {
    новоеПоколение();
  }

  /**
   * «Назад» на экране «Игра с другом». Здесь два разных «выхода», и путать
   * их нельзя. За столом кнопка «В меню» — это настоящий уход из партии,
   * и она честно предупреждает, что друг останется один. А на этом экране
   * человек за стол ещё не сел: сюда попадают из меню, и как только возврат
   * удался, экран сам сменяется на стол или на плашку с кодом. Значит,
   * «Назад» здесь означает «передумал возвращаться прямо сейчас» —
   * партию не рвём, ключи оставляем, кнопка возврата в меню остаётся.
   */
  function вернутьсяВМеню() {
    // Если мы всё-таки за столом (так сюда не попасть, но пусть будет
    // надёжно) — это честный выход, и друга надо предупредить.
    if (вПартии || (код && пропуск)) покинутьПартию();
    else отменитьВозврат();
    // Иначе «Возвращаемся в вашу игру…» так и висит на скрытом экране.
    сказать('сообщение-друга', '');
    обновитьКнопкуВозврата();
    показатьЭкран('экран-меню');
  }

  function накнопку(id, действие) {
    const кнопка = узел(id);
    if (!кнопка) {
      console.warn('Игра вдвоём: не нашёл кнопку «' + id + '». ' +
                   'Скорее всего, браузер показывает старую страницу — обновите её (Ctrl+F5).');
      return;
    }
    кнопка.addEventListener('click', действие);
  }

  function подключить() {
    накнопку('кнопка-с-другом', открытьЭкранДруга);
    накнопку('кнопка-вернуться-в-игру', открытьЭкранДруга);
    накнопку('кнопка-создать-игру', создатьИгру);
    накнопку('кнопка-войти-по-коду', открытьЭкранВхода);
    накнопку('кнопка-друг-назад', вернутьсяВМеню);
    накнопку('кнопка-копировать-код', скопироватьКод);
    накнопку('кнопка-комната-отмена', отменитьКомнату);
    накнопку('кнопка-войти', войтиПоКоду);
    накнопку('кнопка-вход-назад', открытьЭкранДруга);
    накнопку('кнопка-посадить-бота', function () {
      действиеПрихожей('бот', 'кнопка-посадить-бота', 'Сажаем бота…');
    });
    накнопку('кнопка-убрать-бота', function () {
      действиеПрихожей('убрать-бота', 'кнопка-убрать-бота', 'Убираем бота…');
    });
    накнопку('кнопка-начать-игру', function () {
      действиеПрихожей('начать', 'кнопка-начать-игру', 'Раздаём карты…');
    });
    накнопку('кнопка-адрес-сервера', переключитьНастройкуАдреса);
    накнопку('кнопка-адрес-из-входа', открытьНастройкуСЭкранаВхода);
    накнопку('кнопка-проверить-адрес', function () {
      проверитьАдресСервера('кнопка-проверить-адрес');
    });
    накнопку('кнопка-сохранить-адрес', сохранитьАдресСервера);
    накнопку('кнопка-стереть-адрес', стеретьАдресСервера);

    // Телефон сам сообщает, что связь пропала или вернулась. Это самый
    // быстрый сигнал: ждать, пока оборвётся висящий запрос, не нужно.
    window.addEventListener('offline', function () {
      if (!вПартии) return;
      связьЕсть = false;
      освежитьСтрокуСвязи();
    });
    window.addEventListener('online', function () {
      if (!вПартии || !код || !пропуск) return;
      // Сеть вернулась — не ждём паузы, спрашиваем состояние сразу.
      const моё = поколение;
      запросОтМеня('/состояние', {}).then(function (ответ) {
        // Пока ответ шёл, человек мог выйти и начать новую игру. Тогда это
        // рассказ о брошенной комнате, и показывать его нельзя.
        if (ответУстарел(моё)) return;
        if (!ответ.ок || !ответ.данные.состояние) return;
        связьВернулась();
        принятьСостояние(ответ.данные.состояние);
      });
    });

    const поле = узел('поле-кода');
    if (поле) {
      // Телефон норовит писать строчными и «исправлять» код в слово.
      поле.addEventListener('input', function () {
        const исправленный = очиститьКод(поле.value);
        if (поле.value !== исправленный) поле.value = исправленный;
      });
      поле.addEventListener('keydown', function (событие) {
        if (событие.key === 'Enter') войтиПоКоду();
      });
    }

    const полеАдреса = узел('поле-адреса');
    if (полеАдреса) {
      полеАдреса.addEventListener('keydown', function (событие) {
        if (событие.key === 'Enter') сохранитьАдресСервера();
      });
    }

    /* В разметке кнопка возврата спрятана. Показать её при первой загрузке
       некому, кроме этой строки: дальше её включает и выключает работа с
       памятью браузера, а перезагрузка страницы — как раз тот случай,
       ради которого кнопку и делали. */
    обновитьКнопкуВозврата();
    // По той же причине показываем вход в настройку адреса, если адрес
    // однажды вписали: после перезагрузки его должно быть где поправить.
    обновитьВходВНастройку();
    // Выбор стола тоже надо показать сразу: без этого человек видит ряды
    // кнопок, ни одна из которых не отмечена, и не понимает, что выбрано.
    подключитьВыборСтола();
  }

  /* -------------------------------------------------------------------
     Наружу — только то, чем пользуется js/game.js
     ------------------------------------------------------------------- */

  window.Сеть = {
    /**
     * Отправить намерение игрока. Обещание никогда не срывается:
     * при любой беде вернётся { ошибкаСвязи: true }, и игра не сломается.
     */
    отправитьХод: function (намерение) {
      if (!код || !пропуск) {
        return Promise.resolve({ принято: false, причина: 'Вы сейчас не в игре с другом' });
      }
      /* Связь уже оборвана, и мы это знаем — ход в никуда не отправляем.
         Иначе каждое нажатие висело бы десять секунд и заканчивалось ничем:
         пока туннель мёртв, запрос всё равно упрётся в ожидание. Лучше
         ответить сразу и словами. Ждать не придётся долго — опрос стучится
         в сервер сам и вернёт игру в строй, как только связь появится. */
      if (!связьЕсть) {
        return Promise.resolve({ принято: false,
          причина: 'Связь с игрой потеряна — ход не отправлен. ' +
                   'Как только связь вернётся, можно будет сходить снова.' });
      }
      const моё = поколение;
      return запросОтМеня('/ход', намерение || {}).then(function (ответ) {
        // Ответ мог опоздать: человек уже вышел и сел за новый стол.
        // Особенно опасен запоздавший «комнаты нет» — он выбросил бы
        // игрока из свежей партии, а друг остался бы за столом один.
        // Пустой ответ игра переживает: она проверяет его на «ничего».
        if (ответУстарел(моё)) return;
        if (ответ.связьСорвалась) {
          связьПотеряна();
          return { ошибкаСвязи: true };
        }
        if (ответ.номер === 404) {
          комнатаПропала();
          return { ошибкаСвязи: true };
        }
        связьВернулась();
        if (ответ.данные.состояние) принятьСостояние(ответ.данные.состояние);
        return {
          принято: Boolean(ответ.данные.принято),
          причина: ответ.данные.причина || ответ.данные.ошибка || null
        };
      });
    },

    покинутьПартию: покинутьПартию,

    /** Идёт ли сейчас сетевая партия — нужно для проверок. */
    вИгре: function () { return вПартии; },

    /** Адрес сервера, с которым работаем. Пригодится при разборе жалоб. */
    адрес: адресСервера
  };

  // Разметка к этому времени готова: файл подключён в конце страницы.
  подключить();

})();
