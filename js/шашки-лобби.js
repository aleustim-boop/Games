/* =====================================================================
   ШАШКИ — ЛОББИ. Каркас дурака: первый шаг — РОВНО ТРИ карточки
   («Играть онлайн», «Играть с ботом», «Позвать друга»), настройки
   переехали на второй шаг (задача владельца 23.09: «сделать по
   эталону с дураком»).

   (Э3 плана штаб/план-единый-стиль.md; правка 23.09 — три карточки.)

   ВТОРОЙ ШАГ — уже существующий #экран-бота-шашек (шашки.html), а не
   новый узел: у него уже были уровень бота и скрытый дублёр контроля
   времени, недостающим было только «показать вместо сразу стартовать».
   Карточка «Играть с ботом» теперь ОТКРЫВАЕТ его (см. «показатьШагБота»
   ниже), а не жмёт «кнопка-с-ботом» сама. Вход «Вдвоём» сюда не уезжал
   насовсем: с 23.09 по 24.09 жил здесь мелкой кнопкой, решением
   владельца 24.09 вернулся на ПЕРВЫЙ шаг (кнопка «лобби-вдвоём», видна
   сразу под тройкой карточек) — см. подробности у самой кнопки ниже.

   ЧЕГО ЗДЕСЬ НЕТ. Ни одного правила игры, ни одного запроса к серверу.
   Этот файл только показывает лобби вместо старого экрана «С кем
   играть» и нажимает за человека уже существующие кнопки — те же,
   что нажимал старый экран. Второй дороги к игре, к сети или к боту
   этот файл не заводит.

   КАК УСТРОЕН ЗАПАСНОЙ ВИД. В шашки.html #экран-режимов по-прежнему
   помечен классом «экран--виден» — это ЕГО экран по умолчанию. Если
   этот файл не загрузится (сбой сети, старая страница в памяти
   телефона) — ничего не изменится, страница откроется на нём,
   и все её кнопки будут работать ровно как до Э3.
   Если файл загрузился — он ниже, при подключении, сам прячет
   #экран-режимов и показывает #экран-лобби вместо него.

   КАК ЛОББИ СТАЛО ГЛАВНЫМ ЭКРАНОМ, А НЕ ВТОРЫМ. Файлы, которые ведут
   игру, — js/шашки-режимы.js, js/шашки-сеть.js, js/шашки-экран.js —
   не правятся ни строкой (задача так и просит); правки шашки.html
   ограничены разметкой (три карточки и кнопка «Вдвоём» в лобби,
   раскрытый контроль времени на #экран-бота-шашек) — ни одного
   id, который слушают эти файлы, не переименовано и не убрано.
   Вместо правки чужих файлов:
     1) при подключении лобби показывается вместо режимов один раз;
     2) window.ШашкиРежимы.показать() и .показатьПоИмени('экран-режимов')
        подменяются на показ лобби — этими дверями пользуются
        js/шашки-сеть.js (мост «вМеню» и «экран») и js/шашки-экран.js
        (кнопка «Другой соперник»), и после подмены они сами того
        не заметив ведут обратно в лобби, а не в старый экран;
     3) у «кнопка-в-меню-шашки» (кнопка «‹» на столе, «В меню» в листе
        «⋯») есть свой закрытый обработчик внутри js/шашки-режимы.js —
        он не ходит через window.ШашкиРежимы и подмену пункта 2 не видит.
        Поэтому на неё здесь навешан ВТОРОЙ слушатель (тот же приём,
        каким в js/шашки-режимы.js устроена кнопка-переходник
        «кнопка-играть»): он срабатывает следом за первым, синхронно,
        до перерисовки страницы. НО показывает лобби не безусловно —
        сперва смотрит, увёл ли первый обработчик и правда на
        «экран-режимов» (см. «показатьЛоббиПослеКнопкиВМеню» ниже):
        если партия идёт и первый обработчик вместо ухода открыл плашку
        подтверждения «Завершить партию?», лобби ждёт — иначе плашка
        оказалась бы висеть поверх уже показанного лобби, а не поверх
        стола (был баг, игроков мгновенно уводило из партии);
     4) у «кнопка-бота-назад» на #экран-бота-шашек тот же самый
        закрытый обработчик из js/шашки-режимы.js (накнопку('кнопка-
        бота-назад', показать) — тоже локальная функция файла, не через
        window.ШашкиРежимы), поэтому подмена пункта 2 её тоже не видит.
        Второй слушатель здесь безусловный (см. «показатьЛоббиПослеШагаБота»
        ниже): партии на этом экране не бывает, спрашивать подтверждение
        не у кого, и первый обработчик уже сделал «экран-режимов»
        видимым к этому моменту — сразу подменяем его на лобби. Через
        js/шашки-телеграм.js той же дверью пользуется и системная
        стрелка Telegram, и кнопка «Назад» самого экрана — она ищет
        открытый экран и жмёт «кнопка-бота-назад» сама (КНОПКА_НАЗАД_НА_
        ЭКРАНЕ['экран-бота-шашек']), так что один перехват чинит оба пути.

   ПРОВЕРКА БЕЗ БРАУЗЕРА. Ниже, до первого обращения к document, лежат
   только чистые данные и функции (уровень бота, слово о серии побед) —
   их и достаёт штабная проверка через module.exports, как это уже
   устроено в js/нижние-вкладки.js и js/лист-ещё.js.
   ===================================================================== */

(function () {
  /* -------------------------------------------------------------------
     СЛОЖНОСТЬ БОТА: чистые данные, без DOM.

     Ключ памяти НОВЫЙ: до Э3 выбор уровня жил только в переменной
     js/шашки-экран.js и не переживал перезапуск игры (обнулялся до
     «обычный» при каждом открытии страницы) — переносить в этом смысле
     было нечего. Имя — латиницей, по правилу проекта.
     ------------------------------------------------------------------- */
  const КЛЮЧ_УРОВНЯ = 'shashki_bot_level';
  const УРОВНИ = ['лёгкий', 'обычный', 'сложный'];

  function проверитьУровень(уровень) {
    return УРОВНИ.indexOf(уровень) !== -1 ? уровень : 'обычный';
  }

  /* -------------------------------------------------------------------
     КОНТРОЛЬ ВРЕМЕНИ (Э3): тот же приём, что и уровень бота выше —
     чистые данные без DOM, свой ключ памяти (новый — переносить нечего),
     действует и на игру с ботом, и на игру вдвоём. По сети часов нет
     вовсе — эта настройка на сетевую партию не влияет (см. js/шашки-
     экран.js: включитьСеть всегда ставит контроль «нет»). */
  const КЛЮЧ_КОНТРОЛЯ = 'shashki_time_control';
  const КОНТРОЛИ = ['нет', 'пять', 'блиц', 'рапид'];

  function проверитьКонтроль(контроль) {
    return КОНТРОЛИ.indexOf(контроль) !== -1 ? контроль : 'нет';
  }

  /* Слово при числе побед подряд: «1 победа», «2 победы», «5 побед». */
  function словоПобед(сколько) {
    const остаток10 = сколько % 10;
    const остаток100 = сколько % 100;
    if (остаток100 >= 11 && остаток100 <= 14) return 'побед';
    if (остаток10 === 1) return 'победа';
    if (остаток10 >= 2 && остаток10 <= 4) return 'победы';
    return 'побед';
  }

  /** Строка карточки профиля про серию — та же честная фраза, что и в
   *  таблице рекордов (см. «Побед подряд…» в js/шашки-рекорды.js). */
  function строкаСерии(серия) {
    const число = Number(серия) || 0;
    return число > 0 ? (число + ' ' + словоПобед(число) + ' подряд') : 'Побед подряд пока нет';
  }

  /* -------------------------------------------------------------------
     ДАЛЬШЕ — ТОЛЬКО БРАУЗЕРНАЯ ЧАСТЬ. В Node (штабная проверка чистых
     функций выше) документа нет, и здесь всё останавливается — сами
     функции и константа ключа всё равно уйдут наружу, см. низ файла.
     ------------------------------------------------------------------- */
  if (typeof document !== 'undefined') {
    const ЭКРАН_ЛОББИ = 'экран-лобби';
    const ЭКРАН_РЕЖИМОВ = 'экран-режимов';

    const лобби = document.getElementById(ЭКРАН_ЛОББИ);
    if (!лобби) return;   // старая страница без этой разметки — жить нечем

    /* Память телефона — свой маленький try/catch, как и в остальных
       файлах шашек (js/шашки-экран.js, js/шашки-рекорды.js): запрещённая
       память не должна ронять лобби, просто уровень не запомнится. */
    function прочитатьУровень() {
      try {
        return проверитьУровень(window.localStorage.getItem(КЛЮЧ_УРОВНЯ));
      } catch (ошибка) {
        return 'обычный';
      }
    }

    function записатьУровень(уровень) {
      try {
        window.localStorage.setItem(КЛЮЧ_УРОВНЯ, уровень);
      } catch (ошибка) { /* запрещённая память — не повод ломать лобби */ }
    }

    let текущийУровень = прочитатьУровень();

    /* ---------- Контроль времени (Э3) ---------- */

    function прочитатьКонтроль() {
      try {
        return проверитьКонтроль(window.localStorage.getItem(КЛЮЧ_КОНТРОЛЯ));
      } catch (ошибка) {
        return 'нет';
      }
    }

    function записатьКонтроль(контроль) {
      try {
        window.localStorage.setItem(КЛЮЧ_КОНТРОЛЯ, контроль);
      } catch (ошибка) { /* запрещённая память — не повод ломать лобби */ }
    }

    let текущийКонтроль = прочитатьКонтроль();

    function нажать(id) {
      const кнопка = document.getElementById(id);
      if (кнопка) кнопка.click();
    }

    /* ---------- Сложность бота и контроль времени (второй шаг) ----------
       До правки 23.09 у лобби был СВОЙ переключатель («лобби-уровень-*»,
       «лобби-время-*»), а настоящие кнопки на #экран-бота-шашек лобби
       нажимало программно и прятало от человека. Теперь своего
       переключателя на первом шаге нет: человек видит и жмёт РЕАЛЬНЫЕ
       кнопки «уровень-*»/«время-*» прямо на #экран-бота-шашек — их клик
       уже слушает js/шашки-экран.js (отметитьУровень/отметитьКонтроль,
       красит «кнопка--активная»). Этому файлу остаётся только запомнить
       выбор в памяти телефона — ВТОРЫМ слушателем на тех же кнопках,
       ничего не трогая в чужом файле. */

    const кнопкиУровня = {
      'лёгкий': document.getElementById('уровень-лёгкий'),
      'обычный': document.getElementById('уровень-обычный'),
      'сложный': document.getElementById('уровень-сложный')
    };
    for (const имя in кнопкиУровня) {
      const кнопка = кнопкиУровня[имя];
      if (!кнопка) continue;
      кнопка.addEventListener('click', function () {
        текущийУровень = имя;
        записатьУровень(текущийУровень);
      });
    }

    const кнопкиКонтроля = {
      'нет': document.getElementById('время-нет'),
      'пять': document.getElementById('время-пять'),
      'блиц': document.getElementById('время-блиц'),
      'рапид': document.getElementById('время-рапид')
    };
    for (const имя in кнопкиКонтроля) {
      const кнопка = кнопкиКонтроля[имя];
      if (!кнопка) continue;
      кнопка.addEventListener('click', function () {
        текущийКонтроль = имя;
        записатьКонтроль(текущийКонтроль);
      });
    }

    /**
     * Второй шаг «Играть с ботом»: показывает #экран-бота-шашек и заранее
     * отмечает на нём сохранённый с прошлого раза уровень и контроль
     * времени (нажатием тех же кнопок, что раньше жались невидимо перед
     * стартом партии) — иначе человек каждый раз видел бы «Обычный»
     * и «Без часов», даже если выбирал другое.
     */
    function показатьШагБота() {
      нажать('уровень-' + текущийУровень);
      нажать('время-' + текущийКонтроль);
      if (window.ШашкиРежимы && typeof window.ШашкиРежимы.показатьПоИмени === 'function') {
        window.ШашкиРежимы.показатьПоИмени('экран-бота-шашек');
      }
    }

    /* ---------- Карточка профиля ---------- */

    /* Фото профиля в кружке аватара лобби — тот же приём, что у дурака
       (см. «освежитьАватар» в js/дурак-путь.js): единственная дверь —
       window.Телеграм.фотоИгрока(), картинка грузится втихую через
       new Image(), и класс-переменную красим только в её onload —
       иначе битый адрес показал бы пустой кружок вместо нарисованного
       человечка. Память последнего подтверждённого адреса — чтобы
       не перегружать одну и ту же картинку при каждом показе лобби.
       Своего id у узла нет (в шашки.html — просто класс «аватар»
       внутри кнопки «лобби-профиль»), поэтому ищем его querySelector'ом. */
    let последнийЗагруженныйАдресАватара = '';
    function освежитьАватар() {
      const узелАватара = document.querySelector('#лобби-профиль .аватар');
      if (!узелАватара) return;
      const адрес = String((window.Телеграм && typeof window.Телеграм.фотоИгрока === 'function'
        ? window.Телеграм.фотоИгрока() : '') || '');
      if (!адрес) {
        узелАватара.classList.remove('аватар--фото');
        узелАватара.style.removeProperty('--фото-аватара');
        return;
      }
      const показатьЗагруженное = function () {
        узелАватара.style.setProperty('--фото-аватара', 'url("' + адрес + '")');
        const принялось = узелАватара.style.getPropertyValue('--фото-аватара').trim() !== '';
        if (!принялось) {
          узелАватара.classList.remove('аватар--фото');
          узелАватара.style.removeProperty('--фото-аватара');
          return;
        }
        узелАватара.classList.add('аватар--фото');
      };
      if (адрес === последнийЗагруженныйАдресАватара) {
        показатьЗагруженное();
        return;
      }
      const картинка = new Image();
      картинка.onload = function () {
        последнийЗагруженныйАдресАватара = адрес;
        // Лобби могли уже закрыть, пока шла загрузка — красить нечего.
        if (!document.body.contains(узелАватара)) return;
        показатьЗагруженное();
      };
      картинка.onerror = function () { /* сеть подвела — молча оставляем человечка */ };
      картинка.src = адрес;
    }

    function освежитьПрофиль() {
      const имя = document.getElementById('лобби-имя');
      if (имя) {
        const изTelegram = window.Телеграм && typeof window.Телеграм.имяИгрока === 'function'
          ? String(window.Телеграм.имяИгрока() || '').trim() : '';
        имя.textContent = изTelegram || 'Вы';
      }
      освежитьАватар();
      const серия = document.getElementById('лобби-серия-текст');
      if (серия) {
        const число = window.ШашкиРекорды && typeof window.ШашкиРекорды.серия === 'function'
          ? window.ШашкиРекорды.серия() : 0;
        серия.textContent = строкаСерии(число);
      }
    }
    освежитьПрофиль();

    /* Профиль освежаем не только при загрузке страницы, но каждый раз,
       когда лобби становится видимым, — двумя путями сразу, тем же
       приёмом, что и у шахмат (см. js/шахматы-лобби.js):
         1) js/шашки-экран.js возвращает в лобби НАПРЯМУЮ переключением
            класса «экран--виден» — при выходе из «Как играть»/«Рекорды»,
            если до них было открыто лобби (см. «вернутьсяСоСлужебного»
            в js/шашки-экран.js); этот файл о существовании
            освежитьПрофиль не знает и знать не должен (граница между
            файлами). Поэтому сторожим сам класс: как только лобби
            становится видимым, откуда бы показ ни пришёл, имя, фото
            и серия обновляются — иначе после «Рекордов» в лобби висела
            бы вчерашняя серия побед;
         2) в настоящем Telegram имя и фото игрока даёт telegram-web-app.js —
            он подключён с «defer» и может ответить ПОЗЖЕ, чем выполнился
            этот файл; тогда лобби успевает показать заглушку раньше, чем
            стало известно настоящее имя. Событие load окна наступает
            заведомо позже — повторяем освежение по нему, и заглушка
            не остаётся навсегда. */
    if (typeof MutationObserver === 'function') {
      const сторожЛобби = new MutationObserver(function () {
        if (лобби.classList.contains('экран--виден')) освежитьПрофиль();
      });
      сторожЛобби.observe(лобби, { attributes: true, attributeFilter: ['class'] });
    }
    try {
      window.addEventListener('load', освежитьПрофиль);
    } catch (ошибка) { /* нет окна — освежать нечего */ }

    /* ---------- Карточки входов: переходники на уже существующие кнопки ----------
       Ни одна из них не заводит новую дорогу к игре, к сети или к боту —
       только нажимает узел, который уже слушают другие файлы. Тот же
       приём, что и у самого дурака (см. «подключитьЗапаснойВходЛобби»
       и «нажатьКнопкуСети» в js/game.js). */

    // «Играть с ботом» больше не начинает партию сама — открывает второй
    // шаг (см. «показатьШагБота» выше), где стоит настоящая кнопка «Начать».
    const кнопкаБоты = document.getElementById('лобби-боты');
    if (кнопкаБоты) кнопкаБоты.addEventListener('click', показатьШагБота);

    // Id переименован с прежнего «лобби-друг» на «лобби-друзья» (задача
    // владельца 23.09) — переходник тот же, «кнопка-с-другом».
    const кнопкаДрузья = document.getElementById('лобби-друзья');
    if (кнопкаДрузья) кнопкаДрузья.addEventListener('click', function () { нажать('кнопка-с-другом'); });

    /* «Вдвоём на одном телефоне» — решение владельца 24.09: кнопка
       вернулась на ПЕРВЫЙ шаг лобби (id «лобби-вдвоём», тот же текст,
       приём и класс, что у шахмат, см. js/шахматы-лобби.js). Раньше вход
       прятался мелкой кнопкой на втором шаге «Играть с ботом»
       (#кнопка-бота-вдвоём, теперь убрана из шашки.html) — второй
       дороги к игре вдвоём не заводим, эта кнопка — единственная. */
    const кнопкаЛоббиВдвоём = document.getElementById('лобби-вдвоём');
    if (кнопкаЛоббиВдвоём) {
      кнопкаЛоббиВдвоём.addEventListener('click', function () {
        // Контроль времени действует и на игру вдвоём — отмечаем той же
        // кнопкой, что и для игры с ботом, до перехода на стол.
        нажать('время-' + текущийКонтроль);
        нажать('кнопка-вдвоём');
      });
    }

    const кнопкаКод = document.getElementById('лобби-код');
    if (кнопкаКод) кнопкаКод.addEventListener('click', function () { нажать('кнопка-войти-по-коду'); });

    const кнопкаПрофиль = document.getElementById('лобби-профиль');
    if (кнопкаПрофиль) {
      кнопкаПрофиль.addEventListener('click', function () {
        if (window.ЭкранРейтинга) window.ЭкранРейтинга.открытьСчёт('шашки');
      });
    }

    /* Кнопки «‹» и «⋯» верхней строки лобби ничего своего не слушают:
       «‹» (id «кнопка-лобби-назад») уже в списке js/шашки-телеграм.js,
       «⋯» (id «кнопка-лобби-ещё») уже в «идОткрывающих» js/шашки-экран.js —
       оба файла находят кнопки лобби по id напрямую. */

    /* -------------------------------------------------------------------
       ПОКАЗАТЬ ЛОББИ ВМЕСТО СТАРОГО ЭКРАНА — см. пояснение в шапке файла.
       ------------------------------------------------------------------- */

    let оригПоказатьПоИмени = null;

    function показатьЛоббиВместоРежимов() {
      // Сперва — обычный показ «экран-режимов»: он прячет доску, итог
      // партии и все прочие экраны так же, как делал это всегда. Дальше
      // остаётся только подменить, какой из двух главных экранов остался
      // видимым.
      if (оригПоказатьПоИмени) оригПоказатьПоИмени(ЭКРАН_РЕЖИМОВ);
      else {
        // Дверь ещё не готова (файлы подключаются в порядке страницы,
        // это первый вызов до неё) — переключаем экраны вручную.
        document.querySelectorAll('#приложение > .экран').forEach(function (э) {
          э.classList.remove('экран--виден');
        });
      }
      const режимов = document.getElementById(ЭКРАН_РЕЖИМОВ);
      if (режимов) режимов.classList.remove('экран--виден');
      лобби.classList.add('экран--виден');
      освежитьПрофиль();   // серия могла обновиться после партии
    }

    function подключитьПодменуЭкранов() {
      if (!window.ШашкиРежимы || typeof window.ШашкиРежимы.показатьПоИмени !== 'function') {
        // js/шашки-режимы.js ещё не подключился (не должно случиться —
        // порядок подключения важен и описан в шашки.html) — лобби всё
        // равно показываем, просто без перехвата «В меню»/сети.
        показатьЛоббиВместоРежимов();
        return;
      }
      оригПоказатьПоИмени = window.ШашкиРежимы.показатьПоИмени;

      window.ШашкиРежимы.показать = показатьЛоббиВместоРежимов;
      window.ШашкиРежимы.показатьПоИмени = function (имя) {
        if (имя === ЭКРАН_РЕЖИМОВ) { показатьЛоббиВместоРежимов(); return; }
        оригПоказатьПоИмени(имя);
      };

      показатьЛоббиВместоРежимов();
    }
    подключитьПодменуЭкранов();

    /* «В меню» на столе (кнопка «‹» и строка листа «⋯») слушает
       js/шашки-режимы.js напрямую, минуя window.ШашкиРежимы, — подмена
       выше её не видит. Второй слушатель на той же кнопке добавлен здесь.

       ГОРЕВШИЙ БАГ: js/шашки-режимы.js подключается раньше этого файла
       (см. порядок в шашки.html) и потому срабатывает на клик ПЕРВЫМ.
       Если партия идёт, он сначала спрашивает подтверждение через
       window.ШашкиЭкран.спроситьЗавершить() — и, пока плашка «Завершить
       партию?» открыта, делает return, НЕ переводя экран на
       «экран-режимов» (стол остаётся видимым, ждёт ответа игрока).
       Прежний второй слушатель показывал лобби безусловно — плашка
       оказывалась висеть уже поверх лобби вместо стола, а «‹» на столе
       мгновенно уводил из партии без вопроса.

       Чиним по РЕЗУЛЬТАТУ первого обработчика, а не переспрашивая
       window.ШашкиЭкран.спроситьЗавершить() второй раз: у него есть
       побочный эффект (реально открывает плашку и ставит часы на паузу),
       и второй вызов в том же клике продублировал бы его. Надёжный
       признак «первый обработчик и правда увёл в меню» — то, что
       «экран-режимов» стал видимым экраном: это делает уйтиВМеню() внутри
       js/шашки-режимы.js, и только когда партия не идёт или плашка
       подтверждения не открылась. */
    function показатьЛоббиПослеКнопкиВМеню() {
      const режимов = document.getElementById(ЭКРАН_РЕЖИМОВ);
      const первыйОбработчикУвёлВМеню = !!(режимов && режимов.classList.contains('экран--виден'));
      if (!первыйОбработчикУвёлВМеню) return;   // партия идёт — открылась плашка подтверждения
      показатьЛоббиВместоРежимов();
    }
    const кнопкаВМеню = document.getElementById('кнопка-в-меню-шашки');
    if (кнопкаВМеню) кнопкаВМеню.addEventListener('click', показатьЛоббиПослеКнопкиВМеню);

    /* «Назад» со второго шага «Играть с ботом» (кнопка-бота-назад) —
       тот же приём, что и «В меню» выше, но проще: партии на этом экране
       не бывает, спрашивать подтверждение не у кого, и первый обработчик
       (накнопку('кнопка-бота-назад', показать) в js/шашки-режимы.js,
       локальная функция файла, минуя window.ШашкиРежимы) уже сделал
       «экран-режимов» видимым к моменту, когда добегает этот, второй,
       слушатель — подменяем безусловно. Той же кнопкой пользуется
       и системная стрелка Telegram (js/шашки-телеграм.js: «назад» находит
       открытый экран «экран-бота-шашек» и жмёт «кнопка-бота-назад» сама),
       так что один перехват чинит оба пути «на первый шаг». */
    const кнопкаБотаНазад = document.getElementById('кнопка-бота-назад');
    if (кнопкаБотаНазад) кнопкаБотаНазад.addEventListener('click', показатьЛоббиВместоРежимов);
  }

  /* Наружу — только чистые данные и функции без DOM, для проверки
     в Node (штаб/…), как у js/нижние-вкладки.js и js/лист-ещё.js. */
  const ШашкиЛобби = {
    проверитьУровень: проверитьУровень, строкаСерии: строкаСерии, КЛЮЧ_УРОВНЯ: КЛЮЧ_УРОВНЯ,
    проверитьКонтроль: проверитьКонтроль, КЛЮЧ_КОНТРОЛЯ: КЛЮЧ_КОНТРОЛЯ
  };
  if (typeof module !== 'undefined' && module.exports) module.exports = ШашкиЛобби;
  if (typeof window !== 'undefined') window.ШашкиЛобби = ШашкиЛобби;
})();
