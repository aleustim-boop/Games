'use strict';

/* =====================================================================
   ШАШКИ — ЭКРАН. Рисует доску и слушает палец.

   Своих правил у этого файла НЕТ ни одного. Он ничего не знает про то,
   кому куда можно ходить, обязателен ли бой и когда простая становится
   дамкой: на каждый такой вопрос отвечает js/шашки-правила.js. Здесь
   только «что показать» и «куда ткнули».

   Так сделано не из красоты. Второе место, где записано то же правило,
   однажды разойдётся с первым, и разошедшееся будут искать неделю —
   в этом проекте так уже бывало. Поэтому: экран спрашивает, правила
   отвечают. Если чего-то спросить нельзя, значит новый вопрос надо
   добавить в правила, а не посчитать здесь «по-быстрому».

   На этом шаге играют двое с одного телефона по очереди: соперника-робота
   нет вовсе, он будет отдельным файлом js/шашки-бот.js.

   Как ходят пальцем:
     • тап по своей шашке — она поднимается, поля для хода подсвечиваются
       (точка — тихий ход, красное кольцо — бой);
     • тап по подсвеченному полю — шашка идёт туда;
     • если бой продолжается, шашка остаётся поднятой и ждёт следующего
       поля, а побитые остаются на доске перечёркнутыми: снимут их только
       в конце всего хода (турецкий удар);
     • тап по самой поднятой шашке — передумал, выбор сброшен.
   ===================================================================== */

(function () {
  const Правила = window.ШашкиПравила;

  const узелДоски = document.getElementById('доска');
  const строкаХода = document.getElementById('строка-хода');
  const экранИтога = document.getElementById('экран-итога');
  const заголовокИтога = document.getElementById('заголовок-итога');
  const причинаИтога = document.getElementById('причина-итога');
  const кнопкаЗаново = document.getElementById('кнопка-заново');
  const кнопкаМеток = document.getElementById('кнопка-метки');
  const кнопкаЕщё = document.getElementById('кнопка-ещё');

  /* Молчащая страница хуже сломанной: человек тыкает в доску и решает,
     что зависла вся игра. Поэтому о пропавших правилах говорим прямо. */
  if (!Правила) {
    if (строкаХода) строкаХода.textContent = 'Правила не загрузились — обновите страницу';
    console.error('js/шашки-правила.js не подключился: экрану не у кого спросить про ходы');
    return;
  }

  const БУКВЫ = 'abcdefgh';
  const ПОКАЗ_ОТКАЗА = 900;      // сколько миллисекунд вздрагивает клетка, куда нельзя

  /* ------------------------------------------------------------------
     Что экран помнит про себя. Про партию он не помнит ничего:
     всё, что можно спросить у правил, спрашивается заново.
     ------------------------------------------------------------------ */
  let партия = null;
  /* Путь, который человек уже набрал пальцем: [откуда, первое поле, …].
     Пусто — никто не поднят. Это НЕ ход: ход случится, когда путь
     дойдёт до конца одной из возможностей. */
  let выбранныйПуть = [];
  /* Ходы правил, у которых путь начинается с набранного. Из них и растут
     подсветка и решение «всё, ход набран». */
  let подходящие = [];
  let показыватьМетки = true;
  let таймерОтказа = null;
  let клеткаОтказа = null;

  const клеткиПоПолю = new Map();   // 'c3' → узел клетки

  /* ==================================================================
     ДОСКА: собираем один раз, дальше только меняем классы.
     Перерисовывать разметку целиком на каждый ход не нужно — от этого
     на телефоне мигает картинка и теряется нажатие.
     ================================================================== */
  function построитьДоску() {
    /* Какие поля игровые, спрашиваем у правил, а не считаем заново:
       «тёмное ли поле» — это тоже правило, и оно уже записано там. */
    const игровые = new Set(Правила.ПОЛЯ);
    const куски = document.createDocumentFragment();

    // Сверху восьмая горизонталь, снизу первая: доска глазами белых.
    for (let ряд = 8; ряд >= 1; ряд--) {
      for (let столбец = 0; столбец < 8; столбец++) {
        const имя = БУКВЫ[столбец] + ряд;
        const игровое = игровые.has(имя);
        const клетка = document.createElement('div');
        клетка.className = 'поле ' + (игровое ? 'поле--тёмное' : 'поле--светлое');

        // Цифры — вдоль левого края, буквы — вдоль нижнего.
        if (столбец === 0) клетка.appendChild(метка('метка-цифра', String(ряд)));
        if (ряд === 1) клетка.appendChild(метка('метка-буква', БУКВЫ[столбец]));

        if (игровое) {
          // Имя поля держим и в разметке — так проверке и человеку
          // в инструментах браузера видно, куда он тыкает.
          клетка.setAttribute('data-поле', имя);
          клеткиПоПолю.set(имя, клетка);
        }
        куски.appendChild(клетка);
      }
    }
    узелДоски.appendChild(куски);
  }

  function метка(класс, текст) {
    const узел = document.createElement('span');
    узел.className = класс;
    узел.textContent = текст;
    return узел;
  }

  /* ==================================================================
     ОТРИСОВКА: всё, что видно, собирается из партии и набранного пути.
     ================================================================== */
  function отрисовать() {
    const ведёмЦепочку = выбранныйПуть.length > 0;
    const прыжковСделано = выбранныйПуть.length - 1;
    const откуда = ведёмЦепочку ? выбранныйПуть[0] : null;
    const держим = ведёмЦепочку ? выбранныйПуть[выбранныйПуть.length - 1] : null;

    /* Кого уже побили в этой цепочке. Списки «путь» и «побитые» идут
       в ногу (это записано в договоре правил): каждый прыжок снимает
       ровно одну фишку, поэтому первые «прыжковСделано» побитых —
       наши. У всех подходящих ходов начало пути одинаковое, значит
       и побитые на пройденных шагах одни и те же — берём у любого. */
    const побитые = new Set(ведёмЦепочку && подходящие.length
      ? подходящие[0].побитые.slice(0, прыжковСделано)
      : []);

    /* Куда можно шагнуть следующим прыжком и будет ли это боем. */
    const можно = new Map();
    for (const ход of подходящие) {
      const следующее = ход.путь[выбранныйПуть.length];
      if (следующее !== undefined) можно.set(следующее, ход.бой);
    }

    /* Какими шашками вообще можно пойти. Когда на доске есть бой,
       правила не отдают тихих ходов вовсе — значит подсветятся ровно
       те, кто обязан бить, и человеку видно, что выбора нет. */
    const могутХодить = new Set();
    if (!ведёмЦепочку && !Правила.партияЗавершена(партия)) {
      for (const ход of Правила.возможныеХоды(партия)) могутХодить.add(ход.откуда);
    }

    /* Как выглядит ведомая шашка прямо сейчас: посреди боя простая
       могла дойти до последней горизонтали и стать дамкой. Спрашиваем
       правила — сами такое не считаем. */
    const цветВРуке = ведёмЦепочку ? Правила.чейХод(партия) : null;
    const дамкаВРуке = ведёмЦепочку && подходящие.length
      ? Правила.дамкаНаШаге(партия, подходящие[0], прыжковСделано)
      : false;

    клеткиПоПолю.forEach(function (клетка, имя) {
      клетка.classList.toggle('поле--выбрано', имя === держим);
      клетка.classList.toggle('поле--можно', можно.get(имя) === false);
      клетка.classList.toggle('поле--можно-бой', можно.get(имя) === true);

      let что = Правила.фишка(партия, имя);
      let вРуке = false;
      if (ведёмЦепочку) {
        // Поднятая шашка ушла с родного поля и стоит там, куда её довели.
        if (имя === откуда) что = null;
        if (имя === держим) {
          что = { цвет: цветВРуке, дамка: дамкаВРуке };
          вРуке = true;
        }
      }
      поставитьФишку(клетка, что, вРуке, побитые.has(имя), могутХодить.has(имя));
    });

    строкаХода.textContent = словаОХоде();
  }

  function поставитьФишку(клетка, что, вРуке, побита, можетХодить) {
    let узел = клетка.querySelector('.фишка');
    if (!что) {
      if (узел) узел.remove();
      return;
    }
    if (!узел) {
      узел = document.createElement('div');
      клетка.appendChild(узел);
    }
    узел.className = 'фишка' +
      (что.цвет === Правила.БЕЛЫЕ ? ' фишка--белая' : ' фишка--чёрная') +
      (что.дамка ? ' фишка--дамка' : '') +
      (вРуке ? ' фишка--в-руке' : '') +
      (побита ? ' фишка--побита' : '') +
      (можетХодить ? ' фишка--может-ходить' : '');
  }

  /** Что написано над доской. Слова наши, а факты — из правил. */
  function словаОХоде() {
    if (Правила.партияЗавершена(партия)) {
      const результат = Правила.итог(партия);
      if (результат.ничья) return 'Ничья';
      return результат.победитель === Правила.БЕЛЫЕ ? 'Выиграли белые' : 'Выиграли чёрные';
    }
    if (выбранныйПуть.length > 1) {
      return 'Бьём дальше: побитые снимутся в конце хода';
    }
    const чьи = Правила.чейХод(партия) === Правила.БЕЛЫЕ ? 'белые' : 'чёрные';
    if (Правила.естьБой(партия)) return 'Ходят ' + чьи + ': есть бой, брать обязательно';
    return 'Ходят ' + чьи;
  }

  /* ==================================================================
     ПАЛЕЦ
     ================================================================== */
  function тап(поле) {
    if (Правила.партияЗавершена(партия)) return;
    // Гасим прошлую красную вспышку сразу: иначе она висит ещё почти
    // секунду поверх уже сделанного хода и выглядит новой жалобой.
    убратьОтказ();

    if (выбранныйПуть.length === 0) {
      поднять(поле);
      return;
    }
    // Тап по самой поднятой шашке — передумал.
    if (поле === выбранныйПуть[выбранныйПуть.length - 1]) {
      сброситьВыбор();
      отрисовать();
      return;
    }
    вести(поле);
  }

  /** Поднять шашку: спрашиваем у правил, куда ей можно. */
  function поднять(поле) {
    const ходы = Правила.ходыФишки(партия, поле);
    if (ходы.length === 0) {
      отказать(поле);
      return;
    }
    выбранныйПуть = [поле];
    подходящие = ходы;
    отрисовать();
  }

  /** Продолжить набор хода: человек назвал очередное поле. */
  function вести(поле) {
    const дальше = подходящие.filter(function (ход) {
      return ход.путь[выбранныйПуть.length] === поле;
    });

    if (дальше.length === 0) {
      /* Пока прыжков не было, человек вправе передумать и взять другую
         шашку. А вот посреди боя менять шашку нельзя: выбранную серию
         боя правила требуют довести до конца. Бросить её можно только
         тапом по самой шашке. */
      if (выбранныйПуть.length === 1 && Правила.ходыФишки(партия, поле).length > 0) {
        поднять(поле);
        return;
      }
      отказать(поле);
      return;
    }

    выбранныйПуть.push(поле);
    подходящие = дальше;

    /* Ход набран, когда путь дошёл до конца одной из возможностей.
       Больше одной такой быть не может: полный путь однозначно задаёт
       и побитых, и превращение. */
    const готовый = подходящие.find(function (ход) {
      return ход.путь.length === выбранныйПуть.length;
    });
    if (готовый) {
      сходить(готовый);
      return;
    }
    отрисовать();
  }

  function сходить(ход) {
    const получилось = Правила.сделатьХод(партия, ход);
    сброситьВыбор();
    if (!получилось) {
      // Такого быть не должно: ход взят из списка самих правил.
      console.error('правила не приняли собственный ход', ход);
      строкаХода.textContent = 'Так походить не вышло — начните ход заново';
      отрисовать();
      return;
    }
    отрисовать();
    if (Правила.партияЗавершена(партия)) показатьИтог();
  }

  function сброситьВыбор() {
    выбранныйПуть = [];
    подходящие = [];
  }

  /* Так ходить нельзя: клетка коротко вспыхивает, а строка над доской
     объясняет словами. Просто «ничего не произошло» человек читает как
     поломку — особенно когда причина в обязательном бое. */
  function отказать(поле) {
    убратьОтказ();
    const клетка = клеткиПоПолю.get(поле);
    if (клетка) {
      клетка.classList.add('поле--отказ');
      клеткаОтказа = клетка;
    }
    строкаХода.textContent = словаОтказа(поле);
    таймерОтказа = setTimeout(function () {
      убратьОтказ();
      отрисовать();
    }, ПОКАЗ_ОТКАЗА);
  }

  function убратьОтказ() {
    clearTimeout(таймерОтказа);
    таймерОтказа = null;
    if (клеткаОтказа) клеткаОтказа.classList.remove('поле--отказ');
    клеткаОтказа = null;
  }

  function словаОтказа(поле) {
    const что = Правила.фишка(партия, поле);
    if (что && что.цвет === Правила.чейХод(партия)) {
      return Правила.естьБой(партия)
        ? 'Этой шашкой нельзя: бить обязана другая'
        : 'Этой шашкой ходить некуда';
    }
    if (что) return 'Это шашка соперника';
    return 'Сюда пойти нельзя';
  }

  /* ==================================================================
     ИТОГ И НАЧАЛО ЗАНОВО
     ================================================================== */
  function показатьИтог() {
    const результат = Правила.итог(партия);
    заголовокИтога.textContent = результат.ничья
      ? 'Ничья'
      : (результат.победитель === Правила.БЕЛЫЕ ? 'Белые выиграли' : 'Чёрные выиграли');
    причинаИтога.textContent = сБольшойБуквы(результат.причина);
    экранИтога.classList.add('экран--виден');
  }

  function сБольшойБуквы(слова) {
    return слова ? слова[0].toUpperCase() + слова.slice(1) : '';
  }

  function начатьЗаново() {
    убратьОтказ();
    партия = Правила.создатьПартию();
    сброситьВыбор();
    экранИтога.classList.remove('экран--виден');
    отрисовать();
  }

  /* ==================================================================
     ПОДКЛЮЧЕНИЕ
     ================================================================== */
  построитьДоску();

  /* Слушаем всю доску целиком, а не каждую клетку: обработчиков один
     вместо тридцати двух, и они не теряются при перерисовке. */
  узелДоски.addEventListener('click', function (событие) {
    const клетка = событие.target.closest('.поле');
    if (!клетка) return;
    const поле = клетка.getAttribute('data-поле');
    if (поле) тап(поле);
  });

  кнопкаЗаново.addEventListener('click', начатьЗаново);
  кнопкаЕщё.addEventListener('click', начатьЗаново);

  кнопкаМеток.addEventListener('click', function () {
    показыватьМетки = !показыватьМетки;
    узелДоски.classList.toggle('доска-шашек--с-метками', показыватьМетки);
    кнопкаМеток.textContent = 'Буквы и цифры: ' + (показыватьМетки ? 'да' : 'нет');
  });

  начатьЗаново();
})();
