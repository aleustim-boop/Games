/**
 * Рисунок карты — колода из набора владельца для стола дурака.
 *
 * ЗАЧЕМ. Владелец прислал набор для нового стола и сказал твёрдо: «карты
 * нужно взять эти, а не из старой колоды!». Поэтому старый рисунок (свои
 * портреты, шесть рубашек) ушёл целиком, а новый повторяет набор:
 * кремовая бумага, буквы J, Q, K, A в углах, классическая раскладка
 * значков, масти — формы из значков набора (img/дурак/значки).
 *
 * ЧТО РИСУЕТСЯ КОДОМ, А ЧТО КАРТИНКОЙ.
 *   — Цифры и тузы рисуются кодом. Главная причина — значения. Картинки
 *     из набора — это вырезки с макета, и достоинство на них нельзя
 *     поменять; нарисованная кодом карта всегда показывает ровно ту масть
 *     и то достоинство, что в игре.
 *   — Валет, дама и король — картинками владельца (img/дурак/валет-пики.jpg
 *     и так далее). Углы на его картинках пустые: букву и масть мы рисуем
 *     поверх сами, так же, как у цифр. Под картинкой лежит заглушка —
 *     крупная буква и масть в тонкой рамке: она видна, только если
 *     картинка не загрузилась.
 *   — Рубашка — тоже картинка владельца (img/дурак/рубашка.jpg).
 *
 * НАРУЖУ отдаём прежние шесть дверей — на них завязана игра (js/game.js):
 *   нарисовать(масть, имя) — лицо карты, узел <svg>;
 *   рубашка(ключ)          — карта рубашкой вверх;
 *   значокМасти(масть)     — один значок масти (для метки козыря);
 *   рубашки(), выбратьРубашку(ключ), какаяРубашка() — выбор рубашки.
 *
 * ЦВЕТ И БУМАГА. Внутри рисунка ничего не покрашено намертво: знаки
 * рисуются цветом «currentColor», то есть тем, что style.css задал самой
 * карте, а бумагу под рисунком красит тоже style.css (фон «.карта»).
 * Оформитель меняет цвета мастей и бумаги в одном месте, как и раньше.
 *
 * УГОЛ КОЗЫРЯ. У каждой карты есть ещё один угол — справа сверху, — но
 * он скрыт. Козырь лежит под колодой, и от него видна только правая
 * полоска: обычный угол слева сверху закрыт колодой. Оформитель
 * показывает этот угол только у козыря под колодой (класс
 * «карта-рисунок__угол-козыря»). Сделано так, а не отдельным рисунком
 * козыря, потому что узел карты живёт всю партию: последнюю карту
 * колоды сдают в руку, и в руке она сама становится обычной — правило
 * оформителя на неё там уже не действует.
 *
 * ГРАНИЦА. Файл ничего не знает про правила игры и ни к чему в игре
 * не обращается. Если его не подключить, игра нарисует карты
 * по-старому, текстом (см. запасной путь в js/game.js).
 */
(function () {
  'use strict';

  // На сервере (Node.js) окна и страницы нет вовсе — там этот файл не нужен
  // и не должен даже пытаться что-то создать.
  if (typeof document === 'undefined' || typeof window === 'undefined') return;

  /* Холст карты. 250 на 350 — привычные пропорции игральной карты
     (2,5 к 3,5 дюйма). Все числа ниже — в этих единицах, а не в точках
     экрана: браузер сам растянет рисунок до настоящего размера карты. */
  const ШИРИНА = 250;
  const ВЫСОТА = 350;

  /* Ключ — тот же значок, которым масть называется в правилах игры
     (js/game.js), чтобы не заводить перевод. Имя нужно для номеров
     деталей склада и для имён файлов с фигурами. */
  const ИМЯ_МАСТИ = {
    '♠': 'пики',
    '♥': 'черви',
    '♦': 'бубны',
    '♣': 'трефы'
  };

  /* Что написано в углу. В правилах игры фигуры зовутся по-русски
     (В, Д, К, Т) — там они и остаются: имена уходят на сервер и по сети.
     Меняется только рисунок: в углах буквы, как на картах из набора. */
  const БУКВА_В_УГЛУ = { 'В': 'J', 'Д': 'Q', 'К': 'K', 'Т': 'A' };

  /* Имена файлов с фигурами: «валет-пики», «дама-трефы», «король-черви». */
  const ИМЯ_ФИГУРЫ = { 'В': 'валет', 'Д': 'дама', 'К': 'король' };

  /**
   * Какие картинки фигур лежат в img/дурак/. Все двенадцать владелец
   * прислал 10 сентября: 400 на 560 точек (ровно 5 к 7, как наш холст),
   * карта во весь кадр, фигура в тонкой рамке посередине, углы пустые.
   *
   * СПИСОК НУЖЕН, ЧТОБЫ НЕ ПРОСИТЬ НЕСУЩЕСТВУЮЩЕЕ. Попроси браузер файл,
   * которого нет, — и в консоли у игрока красная ошибка 404. Поэтому
   * картинку берём только тогда, когда её имя здесь записано; фигура
   * без имени в списке рисуется заглушкой.
   *
   * Заменили картинку тем же именем — дописать хвост '?v=2', иначе
   * телефон покажет прежнюю из своей памяти.
   */
  const КАРТИНКИ_ФИГУР = [
    'валет-пики.jpg', 'дама-пики.jpg', 'король-пики.jpg',
    'валет-черви.jpg', 'дама-черви.jpg', 'король-черви.jpg',
    'валет-бубны.jpg', 'дама-бубны.jpg', 'король-бубны.jpg',
    'валет-трефы.jpg', 'дама-трефы.jpg', 'король-трефы.jpg'
  ];

  /* Рубашка от владельца: 400 на 560, во весь кадр, со светлой рамкой
     по краю. Хвост ?v= — по той же причине, что и у фигур. */
  const ФАЙЛ_РУБАШКИ = 'рубашка.jpg?v=1';

  /* Шрифт углов. Нужны прямые цифры одной высоты — у Georgia, которой
     карты рисовались раньше, цифры «старого стиля»: 9 свисает вниз,
     6 торчит вверх, и «10» в углу выходит кривым. Times есть на iPhone
     и на компьютерах, на Android его заменит Noto Serif — оба с прямыми
     цифрами и узкие, как буквы на картах из набора. */
  const ШРИФТ = "'Times New Roman', Times, 'Noto Serif', 'Liberation Serif', serif";

  /* Откуда брать картинки. Путь считаем от самого этого файла, а не от
     страницы: тогда картинка найдётся, даже если файл подключит страница
     из другой папки (например, стенд проверки в tests/). */
  const АДРЕС_ФАЙЛА = (document.currentScript && document.currentScript.src) || '';

  function путьКартинки(имяФайла) {
    if (АДРЕС_ФАЙЛА) {
      try {
        return new URL('../img/дурак/' + имяФайла, АДРЕС_ФАЙЛА).href;
      } catch (ошибка) {
        // старый браузер без URL — ниже возьмём путь от страницы
      }
    }
    return 'img/дурак/' + имяФайла;
  }

  /* ---------- Склад деталей ----------

     Все повторяющиеся детали описаны РОВНО ОДИН РАЗ в скрытом складе
     <svg> внизу страницы, а карты на них только ссылаются через <use>.
     Поэтому 52 карты весят немногим больше одной. */

  /**
   * Масти — контуры из значков набора (img/дурак/значки/*.svg), каждая
   * в своём квадрате 24 на 24. Замерено в браузере: все четыре контура
   * укладываются в этот квадрат целиком, запас по краям не нужен.
   * Одна и та же масть ставится и крупно в середину туза, и мелко в угол.
   */
  function складМастей() {
    return (
      '<symbol id="колода-черви" viewBox="0 0 24 24">' +
        '<path d="M12 21 3 12C-3 4 7-2 12 5c5-7 15-1 9 7Z"/>' +
      '</symbol>' +
      '<symbol id="колода-пики" viewBox="0 0 24 24">' +
        '<path d="M12 1 3 10c-6 7 3 12 8 7L8 23h8l-3-6c5 5 14 0 8-7Z"/>' +
      '</symbol>' +
      '<symbol id="колода-бубны" viewBox="0 0 24 24">' +
        '<path d="m12 1 10 11-10 11L2 12Z"/>' +
      '</symbol>' +
      '<symbol id="колода-трефы" viewBox="0 0 24 24">' +
        '<path d="M8 9a5 5 0 1 1 8 0c9-3 10 11 2 10-2 0-4-1-5-3l3 7H8l3-7c-1 2-3 3-5 3C-2 20-1 6 8 9Z"/>' +
      '</symbol>'
    );
  }

  /* Скругление лица карты — по нему обрезается картинка фигуры, чтобы её
     прямые углы не торчали за скруглённый край. Настоящий край карты
     задаёт style.css; это только страховка на случай, если там скругление
     станет меньше. */
  const СКРУГЛЕНИЕ_ЛИЦА = 16;

  /* Одно скругление на лицо и на рубашку: картинки владельца сделаны
     прямоугольными, во весь кадр, и без обрезки их углы торчали бы. */
  function складОбрезов() {
    return (
      '<clipPath id="колода-обрез-лица">' +
        '<rect x="0" y="0" width="' + ШИРИНА + '" height="' + ВЫСОТА + '" ' +
        'rx="' + СКРУГЛЕНИЕ_ЛИЦА + '"/>' +
      '</clipPath>'
    );
  }

  /**
   * Картинка во весь холст, обрезанная по скруглённому краю. Пропорции
   * картинок владельца те же, что у холста (5 к 7), поэтому «slice»
   * ничего не срезает; он нужен на случай, если картинку заменят другой
   * пропорции: тогда она не сплющится, а лишь потеряет полоску по краю.
   */
  function картинкаВоВесьХолст(файл, класс) {
    const адрес = путьКартинки(файл);
    return '<image class="' + класс + '" href="' + адрес + '" xlink:href="' + адрес + '" ' +
      'x="0" y="0" width="' + ШИРИНА + '" height="' + ВЫСОТА + '" ' +
      'preserveAspectRatio="xMidYMid slice" clip-path="url(#колода-обрез-лица)"/>';
  }

  /* Запасная рубашка — ПОД картинкой: поле цвета рубашки, вокруг него
     кремовая бумага карты. Картинка непрозрачная и во весь холст, поэтому
     запасную видно, только если картинка не загрузилась. Класс
     «рубашка__фон» — тот, которым style.css уже красит поле рубашки. */
  const ЗАПАСНАЯ_РУБАШКА =
    '<rect class="рубашка__фон" x="14" y="14" width="222" height="322" rx="10" fill="#6e2233"/>';

  /** Сама рубашка: картинка владельца во весь холст, под ней запасная. */
  function разметкаРубашкиНабора() {
    return ЗАПАСНАЯ_РУБАШКА + картинкаВоВесьХолст(ФАЙЛ_РУБАШКИ, 'рубашка-рисунок__картинка');
  }

  /**
   * Не доехавшую картинку убрать с карты.
   *
   * Зачем: вместо картинки, которая не загрузилась, браузер рисует значок
   * «битой картинки» — во всю карту, поверх запасного рисунка (проверено
   * в Chrome: картинку короля не пустили, и на карте встал пейзаж с горкой).
   * Убрали картинку — открылось то, что лежит под ней: у фигуры заглушка,
   * у рубашки запасное поле.
   */
  function убиратьНеДоехавшие(узел) {
    if (!узел || typeof узел.querySelectorAll !== 'function') return узел;
    const картинки = узел.querySelectorAll('image');
    for (let i = 0; i < картинки.length; i++) {
      const картинка = картинки[i];
      картинка.addEventListener('error', function () {
        if (картинка.parentNode) картинка.parentNode.removeChild(картинка);
      });
    }
    return узел;
  }

  /**
   * Рубашки для выбора. Сейчас она одна — из набора: старые шесть ушли
   * вместе со старой колодой. Список и выбор оставлены, потому что на них
   * опирается экран «Оформление» в js/game.js; ключ у рубашки новый, так
   * что выбор старой рубашки, сохранённый у игрока в облаке, просто
   * не узнаётся, и остаётся эта.
   */
  const РУБАШКИ = [
    { ключ: 'классика', имя: 'Классика', разметка: разметкаРубашкиНабора }
  ];

  /** Какая рубашка сейчас выбрана. По умолчанию первая в списке. */
  let выбранная = РУБАШКИ[0].ключ;

  /** Найти рубашку по ключу. Незнакомый ключ — берём первую. */
  function найтиРубашку(ключ) {
    for (const р of РУБАШКИ) if (р.ключ === ключ) return р;
    return РУБАШКИ[0];
  }

  /**
   * Перерисовать общий образец рубашки.
   *
   * Все карты рубашкой вверх ссылаются на ОДИН образец («колода-рубашка»),
   * а смена варианта перерисовывает его начинку. Браузер сам обновляет
   * все ссылки разом — и колода, и рука соперника меняются в тот же миг,
   * даже посреди партии.
   */
  function применитьРубашку() {
    const образец = document.getElementById('колода-рубашка');
    if (!образец) return;
    образец.innerHTML = найтиРубашку(выбранная).разметка();
    убиратьНеДоехавшие(образец);
  }

  /** Один раз положить склад на страницу. Второй раз ничего не делает. */
  function поставитьСклад() {
    if (document.getElementById('колода-склад')) return;
    загрузитьЗаранее();
    const обёртка = document.createElement('div');
    обёртка.innerHTML =
      '<svg id="колода-склад" xmlns="http://www.w3.org/2000/svg" ' +
      'xmlns:xlink="http://www.w3.org/1999/xlink" ' +
      'width="0" height="0" aria-hidden="true" focusable="false" ' +
      'style="position:absolute;width:0;height:0;overflow:hidden">' +
      складМастей() + складОбрезов() +
      // Начинку образца кладёт «применитьРубашку» — сразу после склада.
      '<symbol id="колода-рубашка" viewBox="0 0 ' + ШИРИНА + ' ' + ВЫСОТА + '"></symbol>' +
      '</svg>';
    const склад = обёртка.firstElementChild;
    (document.body || document.documentElement).appendChild(склад);
    применитьРубашку();
  }

  /* ---------- Сборка карты ---------- */

  /** Ссылка на складскую деталь. */
  function деталь(номер, x, y, ширина, высота, поворот) {
    return '<use href="#' + номер + '" xlink:href="#' + номер + '" ' +
      'x="' + x + '" y="' + y + '" width="' + ширина + '" height="' + высота + '"' +
      (поворот ? ' transform="' + поворот + '"' : '') + '/>';
  }

  /** Значок масти с центром в точке. Перевёрнутый — как в нижней половине карты. */
  function значок(масть, центрX, центрY, размер, вверхНогами) {
    const номер = 'колода-' + ИМЯ_МАСТИ[масть];
    const поворот = вверхНогами ? 'rotate(180 ' + центрX + ' ' + центрY + ')' : '';
    return деталь(номер, центрX - размер / 2, центрY - размер / 2, размер, размер, поворот);
  }

  /** Что написать в углу: цифру как есть, фигуру и туза — латинской буквой. */
  function надписьУгла(имя) {
    return БУКВА_В_УГЛУ[имя] || имя;
  }

  /* Где стоит угол. Середина столбика «достоинство и масть» — 31 от края:
     в руке карты лежат внахлёст и от каждой видна узкая левая полоска,
     поэтому угол прижат к самому краю. Масть — под достоинством.

     Размеры сверены с набором в одном масштабе: десятка пик из набора
     и наша рядом, обе шириной 180 точек. В руке на макете цифры в углу
     чуть крупнее, чем на столе, — взяли крупные: в тесной руке угол —
     единственное, что видно от карты. */
  const УГОЛ_СЕРЕДИНА = 31;
  const УГОЛ_ЛИНИЯ_ТЕКСТА = 62;
  const УГОЛ_КЕГЛЬ = 60;
  const УГОЛ_МАСТЬ_Y = 92;
  const УГОЛ_МАСТЬ_РАЗМЕР = 32;

  /* «10» — единственное достоинство из двух знаков. Раньше его сжимали
     на глаз под один шрифт, но шрифты у телефонов разные, и у каждого
     своя ширина цифр. Теперь ширину «10» задаём прямо (textLength):
     браузер сам ужмёт цифры любого шрифта ровно до неё. 50 единиц —
     место между краем карты и столбиком значков середины (он начинается
     с 60). */
  const ШИРИНА_ДЕСЯТКИ = 50;

  /* Широкие буквы фигур. На картинках владельца фигура стоит в тонкой
     рамке, и её левая линия проходит в 51 единице от края (82 из 400
     точек картинки). Q и K при нашем кегле шириной около 46 и задевали эту
     линию — видно на крупном снимке всех двенадцати фигур. Поэтому только
     их ужимаем по ширине до 40 и сдвигаем на 3 единицы к краю карты: до
     рамки остаётся три единицы, а высота буквы та же, что у соседок.
     J узкая и в запасе, у туза и цифр рамки нет. */
  const ШИРОКИЕ_БУКВЫ = { 'Q': 40, 'K': 40 };
  const СДВИГ_ШИРОКОЙ_К_КРАЮ = 3;

  /**
   * Один угол: достоинство, под ним масть. Центр столбика — «середина»;
   * так один и тот же угол ставится и слева, и справа (для козыря).
   */
  function столбикУгла(масть, имя, середина) {
    const надпись = надписьУгла(имя);
    const двузначное = надпись.length > 1;
    const широкая = ШИРОКИЕ_БУКВЫ[надпись] || 0;
    /* Куда «к середине карты»: у левого угла вправо, у правого (угол
       козыря) влево. Двузначное «10» сдвигаем на две единицы к середине —
       так у него остаётся запас от края. Широкую букву — на три к краю,
       подальше от рамки фигуры. */
    const кСередине = середина < ШИРИНА / 2 ? 1 : -1;
    let x = середина;
    if (двузначное) x += кСередине * 2;
    else if (широкая) x -= кСередине * СДВИГ_ШИРОКОЙ_К_КРАЮ;
    const ширинаНадписи = двузначное ? ШИРИНА_ДЕСЯТКИ : широкая;
    const сжатие = ширинаНадписи
      ? ' textLength="' + ширинаНадписи + '" lengthAdjust="spacingAndGlyphs"'
      : '';
    return '<text x="' + x + '" y="' + УГОЛ_ЛИНИЯ_ТЕКСТА + '" text-anchor="middle" ' +
      'font-size="' + УГОЛ_КЕГЛЬ + '" font-family="' + ШРИФТ + '" font-weight="700" ' +
      'fill="currentColor"' + сжатие + '>' + надпись + '</text>' +
      значок(масть, середина, УГОЛ_МАСТЬ_Y, УГОЛ_МАСТЬ_РАЗМЕР, false);
  }

  /** Два обычных угла: левый верхний и он же вверх ногами в правом нижнем. */
  function углыКарты(масть, имя) {
    const угол = столбикУгла(масть, имя, УГОЛ_СЕРЕДИНА);
    return '<g class="карта-рисунок__угол">' + угол + '</g>' +
      '<g class="карта-рисунок__угол" transform="rotate(180 ' + ШИРИНА / 2 + ' ' + ВЫСОТА / 2 + ')">' +
        угол +
      '</g>';
  }

  /**
   * Угол козыря — справа сверху, не перевёрнутый. Скрыт атрибутом, а не
   * правилом: атрибут в рисунке — самая слабая мерка, и одно правило
   * оформителя («visibility: visible» у козыря под колодой) его перебивает.
   * Без такого правила карта везде выглядит обычной.
   */
  function уголКозыря(масть, имя) {
    return '<g class="карта-рисунок__угол-козыря" visibility="hidden">' +
      столбикУгла(масть, имя, ШИРИНА - УГОЛ_СЕРЕДИНА) +
      '</g>';
  }

  /**
   * Где стоят значки в середине — классическая раскладка, как на картах
   * набора (сверено с десяткой пик и девяткой бубен на макете).
   * Ключ — сколько значков, значение — точки по холсту 250 на 350.
   * У семёрки седьмой значок стоит между верхней парой и средней, а не
   * седьмым в столбик: именно по этому узору карту узнают не считая.
   * Двойки–пятёрки нужны большой колоде: на пятерых-шестерых игра берёт
   * колоду в 52 карты.
   */
  const ЛЕВО = 84;
  const ЦЕНТР = 125;
  const ПРАВО = 166;
  const ВЕРХ = 76;
  const НИЗ = 274;
  const СЕРЕДИНА = 175;

  const РАСКЛАДКИ = {
    2: [[ЦЕНТР, ВЕРХ], [ЦЕНТР, НИЗ]],
    3: [[ЦЕНТР, ВЕРХ], [ЦЕНТР, СЕРЕДИНА], [ЦЕНТР, НИЗ]],
    4: [[ЛЕВО, ВЕРХ], [ПРАВО, ВЕРХ], [ЛЕВО, НИЗ], [ПРАВО, НИЗ]],
    5: [[ЛЕВО, ВЕРХ], [ПРАВО, ВЕРХ], [ЦЕНТР, СЕРЕДИНА], [ЛЕВО, НИЗ], [ПРАВО, НИЗ]],
    6: [[ЛЕВО, ВЕРХ], [ПРАВО, ВЕРХ], [ЛЕВО, СЕРЕДИНА], [ПРАВО, СЕРЕДИНА],
        [ЛЕВО, НИЗ], [ПРАВО, НИЗ]],
    7: [[ЛЕВО, ВЕРХ], [ПРАВО, ВЕРХ], [ЦЕНТР, 125], [ЛЕВО, СЕРЕДИНА], [ПРАВО, СЕРЕДИНА],
        [ЛЕВО, НИЗ], [ПРАВО, НИЗ]],
    8: [[ЛЕВО, ВЕРХ], [ПРАВО, ВЕРХ], [ЦЕНТР, 125], [ЛЕВО, СЕРЕДИНА], [ПРАВО, СЕРЕДИНА],
        [ЦЕНТР, 225], [ЛЕВО, НИЗ], [ПРАВО, НИЗ]],
    9: [[ЛЕВО, ВЕРХ], [ПРАВО, ВЕРХ], [ЛЕВО, 142], [ПРАВО, 142], [ЦЕНТР, СЕРЕДИНА],
        [ЛЕВО, 208], [ПРАВО, 208], [ЛЕВО, НИЗ], [ПРАВО, НИЗ]],
    10: [[ЛЕВО, ВЕРХ], [ПРАВО, ВЕРХ], [ЦЕНТР, 109], [ЛЕВО, 142], [ПРАВО, 142],
         [ЛЕВО, 208], [ПРАВО, 208], [ЦЕНТР, 241], [ЛЕВО, НИЗ], [ПРАВО, НИЗ]]
  };

  /* Размер значка середины. Контуры набора занимают почти весь свой
     квадрат, так что видимый значок — около 44 единиц, шестая часть
     ширины карты, как на десятке пик в наборе. */
  const РАЗМЕР_ЗНАЧКА = 48;

  /* Туз в наборе — не огромная масть во всю карту, а спокойный значок
     чуть крупнее обычного (сверено с тузом червей на макете). */
  const РАЗМЕР_ТУЗА = 78;

  /** Середина числовой карты: значки по раскладке, нижняя половина — вверх ногами. */
  function серединаЧисловой(масть, сколько) {
    const точки = РАСКЛАДКИ[сколько] || [];
    let рисунок = '';
    for (const точка of точки) {
      рисунок += значок(масть, точка[0], точка[1], РАЗМЕР_ЗНАЧКА, точка[1] > СЕРЕДИНА);
    }
    return рисунок;
  }

  /** Середина туза — одна масть посередине. */
  function серединаТуза(масть) {
    return значок(масть, ЦЕНТР, СЕРЕДИНА, РАЗМЕР_ТУЗА, false);
  }

  /** Имя файла с этой фигурой из списка готовых — или пустая строка. */
  function файлФигуры(масть, имя) {
    const основа = ИМЯ_ФИГУРЫ[имя] + '-' + ИМЯ_МАСТИ[масть];
    for (const файл of КАРТИНКИ_ФИГУР) {
      if (файл.split('.')[0] === основа) return файл;
    }
    return '';
  }

  /**
   * Заглушка фигуры — запасной путь. Нарочно не притворяется портретом:
   * крупная буква и масть в тонкой рамке, — видно, что за карта.
   * Кладётся ПОД картинку владельца: картинка непрозрачная и во весь
   * холст, поэтому, загрузившись, закрывает заглушку целиком. А не
   * загрузилась (плохая связь, файл не доехал) — карта не останется
   * пустой бумагой с одними углами.
   */
  function заглушкаФигуры(масть, имя) {
    return '<g class="карта-рисунок__заглушка">' +
      '<rect x="60" y="64" width="130" height="222" rx="12" fill="none" ' +
      'stroke="currentColor" stroke-opacity="0.35" stroke-width="3"/>' +
      '<text x="' + ЦЕНТР + '" y="196" text-anchor="middle" font-size="124" ' +
      'font-family="' + ШРИФТ + '" font-weight="700" fill="currentColor">' +
      надписьУгла(имя) + '</text>' +
      значок(масть, ЦЕНТР, 242, 50, false) +
      '</g>';
  }

  /** Что рисуем в середине — зависит от достоинства. */
  function серединаКарты(масть, имя) {
    if (имя === 'Т') return серединаТуза(масть);
    if (ИМЯ_ФИГУРЫ[имя]) {
      const файл = файлФигуры(масть, имя);
      const заглушка = заглушкаФигуры(масть, имя);
      return файл ? заглушка + картинкаВоВесьХолст(файл, 'карта-рисунок__фигура') : заглушка;
    }
    return серединаЧисловой(масть, parseInt(имя, 10));
  }

  /** Знакомое ли достоинство: цифры от 2 до 10 или фигура, или туз. */
  function знакомоеДостоинство(имя) {
    if (имя === 'Т' || ИМЯ_ФИГУРЫ[имя]) return true;
    return Object.prototype.hasOwnProperty.call(РАСКЛАДКИ, имя);
  }

  /** Готовый узел из строчки с разметкой. */
  function узелИзСтрочки(строчка) {
    const обёртка = document.createElement('div');
    обёртка.innerHTML = строчка;
    return обёртка.firstElementChild;
  }

  /** Начало любого рисунка карты. Тянется на всю карту, какого бы та ни была размера. */
  function началоХолста(класс) {
    return '<svg class="' + класс + '" xmlns="http://www.w3.org/2000/svg" ' +
      'xmlns:xlink="http://www.w3.org/1999/xlink" ' +
      'viewBox="0 0 ' + ШИРИНА + ' ' + ВЫСОТА + '" preserveAspectRatio="none" ' +
      'aria-hidden="true" focusable="false" ' +
      'style="display:block;width:100%;height:100%">';
  }

  /**
   * Лицо карты. Возвращает готовый узел <svg>.
   * Незнакомая масть или достоинство — возвращаем null: пусть игра нарисует
   * карту по-старому, текстом, — это лучше пустого места.
   *
   * Порядок слоёв: заглушка, над ней картинка фигуры, над ними углы —
   * у владельца на картинках углы пустые как раз под них.
   */
  function нарисовать(масть, имя) {
    if (!ИМЯ_МАСТИ[масть] || !знакомоеДостоинство(имя)) return null;
    поставитьСклад();
    let класс = 'карта-рисунок';
    if (ИМЯ_ФИГУРЫ[имя]) {
      класс += файлФигуры(масть, имя) ? ' карта-рисунок--фигура' : ' карта-рисунок--заглушка';
    }
    const рисунок = началоХолста(класс) +
      '<g fill="currentColor">' +
        серединаКарты(масть, имя) +
        углыКарты(масть, имя) +
        уголКозыря(масть, имя) +
      '</g></svg>';
    return убиратьНеДоехавшие(узелИзСтрочки(рисунок));
  }

  /**
   * Карта рубашкой вверх.
   *
   * Без довода рисуется ВЫБРАННАЯ рубашка, и рисуется ссылкой на общий
   * образец — такая карта сама переоденется, если рубашку сменят.
   * С доводом рисуется именно этот вариант и навсегда — это для экрана
   * выбора, где образцы лежат рядом и меняться не должны.
   */
  function рубашка(ключ) {
    поставитьСклад();
    if (ключ) {
      return убиратьНеДоехавшие(узелИзСтрочки(
        началоХолста('рубашка-рисунок рубашка-рисунок--образец') +
        найтиРубашку(ключ).разметка() +
        '</svg>'
      ));
    }
    return узелИзСтрочки(
      началоХолста('рубашка-рисунок') +
      деталь('колода-рубашка', 0, 0, ШИРИНА, ВЫСОТА, '') +
      '</svg>'
    );
  }

  /** Список рубашек для экрана выбора: ключ и человеческое имя. */
  function рубашки() {
    return РУБАШКИ.map(function (р) { return { ключ: р.ключ, имя: р.имя }; });
  }

  /**
   * Выбрать рубашку. Возвращает true, если ключ знакомый; на незнакомом
   * ключе ничего не меняет и возвращает false — тогда остаётся прежняя.
   * Где хранить выбор, этот файл не знает: его дело — рисовать.
   */
  function выбратьРубашку(ключ) {
    let есть = false;
    for (const р of РУБАШКИ) if (р.ключ === ключ) есть = true;
    if (!есть) return false;
    выбранная = ключ;
    поставитьСклад();
    применитьРубашку();
    return true;
  }

  /** Какая рубашка выбрана сейчас. */
  function какаяРубашка() {
    return выбранная;
  }

  /**
   * Один значок масти сам по себе — для метки козыря рядом со столом.
   * Цвет тот же приём: currentColor, то есть цвет того места, куда поставили.
   */
  function значокМасти(масть) {
    if (!ИМЯ_МАСТИ[масть]) return null;
    поставитьСклад();
    return узелИзСтрочки(
      '<svg class="значок-масти" xmlns="http://www.w3.org/2000/svg" ' +
      'xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 24 24" ' +
      'aria-hidden="true" focusable="false" ' +
      'style="display:inline-block;width:1em;height:1em;vertical-align:-0.12em;fill:currentColor">' +
      деталь('колода-' + ИМЯ_МАСТИ[масть], 0, 0, 24, 24, '') +
      '</svg>'
    );
  }

  /**
   * Попросить все картинки колоды разом, как только понадобилась первая
   * карта. Зовётся один раз — из «поставитьСклад».
   *
   * Почему не при открытии страницы: картинки весят около 700 КБ, а
   * страница открывается витриной, и человек мог прийти в шахматы. Почему
   * не по одной, когда карта впервые попадёт на экран: тогда каждая фигура
   * показывалась бы заглушкой, пока догружается. Рубашка стоит первой —
   * она нужна сразу, на колоде и в руке соперника.
   */
  function загрузитьЗаранее() {
    if (typeof Image !== 'function') return;
    const файлы = [ФАЙЛ_РУБАШКИ].concat(КАРТИНКИ_ФИГУР);
    for (const файл of файлы) {
      const картинка = new Image();
      картинка.src = путьКартинки(файл);
    }
  }

  window.КолодаРисунок = {
    нарисовать: нарисовать,
    рубашка: рубашка,
    значокМасти: значокМасти,
    рубашки: рубашки,
    выбратьРубашку: выбратьРубашку,
    какаяРубашка: какаяРубашка
  };
})();
