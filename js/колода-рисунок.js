/**
 * Рисунок карты — вектором, без картинок и библиотек.
 *
 * ЗАЧЕМ. Раньше карта была белым прямоугольником с текстом «6♠»: значок масти
 * брался из шрифта телефона, а шрифты у всех разные — на части Android черва
 * выходит контуром, а не залитой. Здесь масти нарисованы своим контуром, и на
 * любом телефоне карта выглядит одинаково.
 *
 * КАК УСТРОЕНО (и почему так дёшево по весу). Все повторяющиеся детали —
 * четыре масти, три фигуры, узор рубашки — описаны РОВНО ОДИН РАЗ в скрытом
 * складе `<svg>` внизу страницы. Каждая карта только ссылается на нужную
 * деталь через `<use>`. Поэтому 36 карт весят немногим больше одной.
 *
 * НАРУЖУ отдаём три двери:
 *   window.КолодаРисунок.нарисовать(масть, имя) — лицо карты, узел <svg>;
 *   window.КолодаРисунок.рубашка()              — карта рубашкой вверх;
 *   window.КолодаРисунок.значокМасти(масть)     — один значок масти (для метки козыря).
 *
 * ЦВЕТ. Внутри рисунка ничего не покрашено намертво: масти и достоинства
 * рисуются цветом «currentColor», то есть тем же, который style.css задал
 * самой карте. Оформитель меняет цвет масти как раньше — в одном месте.
 *
 * ГРАНИЦА. Файл ничего не знает про правила игры и ни к чему в игре
 * не обращается. Если его не подключить, игра просто нарисует карты
 * по-старому (см. запасной путь в js/game.js).
 */
(function () {
  'use strict';

  // На сервере (Node.js) окна и страницы нет вовсе — там этот файл не нужен
  // и не должен даже пытаться что-то создать.
  if (typeof document === 'undefined' || typeof window === 'undefined') return;

  /* Холст карты. 250 на 350 — это привычные пропорции игральной карты
     (2,5 к 3,5 дюйма). Все числа ниже — в этих же единицах, а не в точках
     экрана: браузер сам растянет рисунок до настоящего размера карты. */
  const ШИРИНА = 250;
  const ВЫСОТА = 350;

  /* Номера складских деталей по масти. Ключ — тот же значок, которым масть
     называется в правилах игры (js/game.js), чтобы не заводить перевод. */
  const ИМЯ_МАСТИ = {
    '♠': 'пики',
    '♥': 'черви',
    '♦': 'бубны',
    '♣': 'трефы'
  };

  /* ---------- Склад деталей ---------- */

  /**
   * Контуры мастей. Рисуются в своём квадрате 100 на 100, поэтому одну и ту же
   * масть можно поставить и крупно в середину туза, и мелко в угол.
   */
  function складМастей() {
    return (
      // Пика: остриё вверх, два плеча и ножка.
      '<symbol id="колода-пики" viewBox="0 0 100 100">' +
        '<path d="M50 4 C44 24 12 40 12 62 C12 76 22 85 34 85 C41 85 46 82 50 77 ' +
        'C54 82 59 85 66 85 C78 85 88 76 88 62 C88 40 56 24 50 4 Z"/>' +
        '<path d="M50 64 C51 79 46 91 33 98 L67 98 C54 91 49 79 50 64 Z"/>' +
      '</symbol>' +
      // Черва: два верхних лепестка и остриё вниз.
      '<symbol id="колода-черви" viewBox="0 0 100 100">' +
        '<path d="M50 94 C22 74 6 56 6 36 C6 20 18 8 32 8 C41 8 47 13 50 20 ' +
        'C53 13 59 8 68 8 C82 8 94 20 94 36 C94 56 78 74 50 94 Z"/>' +
      '</symbol>' +
      // Буба: ромб со слегка вогнутыми боками — так он живее прямого ромба.
      '<symbol id="колода-бубны" viewBox="0 0 100 100">' +
        '<path d="M50 3 C61 26 74 42 88 50 C74 58 61 74 50 97 ' +
        'C39 74 26 58 12 50 C26 42 39 26 50 3 Z"/>' +
      '</symbol>' +
      // Крестя: три круга и ножка.
      '<symbol id="колода-трефы" viewBox="0 0 100 100">' +
        '<circle cx="50" cy="27" r="20"/><circle cx="26" cy="61" r="20"/>' +
        '<circle cx="74" cy="61" r="20"/>' +
        '<path d="M50 53 C52 71 46 87 32 97 L68 97 C54 87 48 71 50 53 Z"/>' +
      '</symbol>'
    );
  }

  /* Краски портретов. Их нарочно мало: в настоящей колоде фигура — это
     несколько плоских пятен, обведённых тёмным, без теней и переходов.
     Так она и переживает уменьшение: пятно остаётся пятном на любом размере.

     ПАЛИТРА ОДНА НА ВСЕ МАСТИ — как в настоящих картах. Раньше одежда
     красилась цветом масти, и король пик выходил в чёрном, а король червей
     в красном; владелец справедливо сказал, что в жизни так не бывает.
     Теперь у фигуры свой наряд: красный плащ, синяя пелерина, золотая
     корона, телесное лицо. А масть узнаётся там, где ей и положено, —
     по достоинству и значку в углу и по мелкому значку рядом с фигурой. */
  const КОНТУР = '#20222b';
  const ПЛАЩ = '#c8322c';     // красный — главное пятно наряда
  const СИНИЙ = '#2f5fa8';    // пелерина, шляпа, рукава
  const ЛИЦО = '#f1d3ae';
  const СВЕТЛОЕ = '#f7f2e6';
  const ЗОЛОТО = '#e6b34a';
  const СТАЛЬ = '#ccd2db';
  const ДЕРЕВО = '#9a6533';

  /** Пара глаз: два коротких штриха. Точки на мелкой карте выглядят сором. */
  function глаза(высота) {
    return '<rect x="37" y="' + высота + '" width="8" height="3.4" rx="1.7" ' +
      'fill="' + КОНТУР + '" stroke="none"/>' +
      '<rect x="55" y="' + высота + '" width="8" height="3.4" rx="1.7" ' +
      'fill="' + КОНТУР + '" stroke="none"/>';
  }

  /**
   * Погрудные портреты валета, дамы и короля — как в настоящей колоде.
   *
   * Каждый нарисован в квадрате 100 на 100 и занимает ВЕРХНЮЮ половину
   * поля карты; нижнюю половину даёт он же, повёрнутый на 180 градусов
   * (см. «серединаФигуры»). Поэтому карту можно взять любой стороной —
   * ради этого настоящие карты так и рисуют.
   *
   * ЧТО ДОЛЖНО ПЕРЕЖИТЬ УМЕНЬШЕНИЕ. В руке карта шириной около 60 точек,
   * портрету достаётся примерно 35 на 32 — там не видно ни черт лица,
   * ни узоров. Поэтому подробностей нет вовсе, а различают фигуры четыре
   * крупных пятна: головной убор, пятно волос или бороды, цвет одежды
   * и предмет в руке — у короля меч, у дамы цветок, у валета алебарда.
   */
  function складПортретов() {
    // Обводка у всех пятен одна: тёмная линия ровной толщины.
    const начало = '<g stroke="' + КОНТУР + '" stroke-width="2.4" ' +
      'stroke-linejoin="round" stroke-linecap="round">';

    /* Наряд собран из двух пятен: широкие плечи одного цвета и пелерина
       у шеи другого. Два цвета вместо одного нужны не для красоты —
       на карте в руке фигура занимает три десятка точек, и два разных
       пятна различаются там куда увереннее, чем одно однотонное. */
    function плечи(цвет) {
      return '<path fill="' + цвет + '" d="M6 100 V84 C6 76 16 70 30 67 L50 80 L70 67 ' +
        'C84 70 94 76 94 84 V100 Z"/>';
    }
    function пелерина(цвет) {
      return '<path fill="' + цвет + '" d="M24 100 C24 85 35 76 50 76 ' +
        'C65 76 76 85 76 100 Z"/>';
    }

    return (
      /* КОРОЛЬ — высокая корона с пятью остриями, широкая светлая борода
         во всё лицо и меч у плеча. Из троих он самый «тяжёлый»: корона
         и борода занимают больше половины портрета. */
      '<symbol id="колода-портрет-король" viewBox="0 0 100 100" preserveAspectRatio="none">' +
        начало +
          // меч: клинок остриём вверх и золотая гарда
          '<path fill="' + СТАЛЬ + '" d="M2 100 V44 L11 26 L20 44 V100 Z"/>' +
          '<rect fill="' + ЗОЛОТО + '" x="0" y="58" width="22" height="8" rx="2"/>' +
          // красный плащ, поверх него синяя пелерина у шеи
          плечи(ПЛАЩ) + пелерина(СИНИЙ) +
          '<path fill="' + СВЕТЛОЕ + '" d="M32 66 L50 82 L68 66 C60 61 40 61 32 66 Z"/>' +
          '<rect fill="' + ЛИЦО + '" x="33" y="26" width="34" height="44" rx="15"/>' +
          '<path fill="' + СВЕТЛОЕ + '" d="M34 46 C34 62 41 72 50 76 C59 72 66 62 66 46 Z"/>' +
          глаза(37) +
          '<path fill="' + ЗОЛОТО + '" d="M26 30 L23 4 L36 18 L50 1 L64 18 L77 4 L74 30 Z"/>' +
          '<rect fill="' + ЗОЛОТО + '" x="25" y="27" width="50" height="10" rx="3"/>' +
        '</g>' +
      '</symbol>' +
      /* ДАМА — невысокий венец, крупная шапка волос вокруг лица и цветок
         у плеча. Её портрет единственный светлый по краям: волосы
         обрамляют лицо и сразу отличают её от короля с бородой. */
      '<symbol id="колода-портрет-дама" viewBox="0 0 100 100" preserveAspectRatio="none">' +
        начало +
          // цветок: стебель и бутон
          '<path fill="none" stroke="#4e7a3a" stroke-width="4" d="M86 100 V64"/>' +
          '<circle fill="' + СВЕТЛОЕ + '" cx="86" cy="54" r="13"/>' +
          '<circle fill="' + ЗОЛОТО + '" cx="86" cy="54" r="5.5" stroke="none"/>' +
          // красное платье, синие рукава-пелерина
          плечи(ПЛАЩ) + пелерина(СИНИЙ) +
          '<path fill="' + СВЕТЛОЕ + '" d="M34 67 L50 82 L66 67 C60 62 40 62 34 67 Z"/>' +
          '<path fill="' + ЗОЛОТО + '" d="M27 36 C27 16 37 9 50 9 C63 9 73 16 73 36 ' +
          'V70 L63 70 V46 H37 V70 L27 70 Z" fill-opacity="0.92"/>' +
          '<rect fill="' + ЛИЦО + '" x="35" y="26" width="30" height="42" rx="14"/>' +
          глаза(40) +
          '<path fill="' + ЗОЛОТО + '" d="M33 22 L31 4 L41 12 L50 0 L59 12 L69 4 L67 22 Z"/>' +
        '</g>' +
      '</symbol>' +
      /* ВАЛЕТ — шляпа с полями и светлым пером, алебарда у плеча.
         Короны у него нет вовсе, и это главное отличие: там, где
         у старших сверкает золото, у валета тёмная шляпа. */
      '<symbol id="колода-портрет-валет" viewBox="0 0 100 100" preserveAspectRatio="none">' +
        начало +
          // алебарда: древко и стальное лезвие
          '<rect fill="' + ДЕРЕВО + '" x="6" y="32" width="9" height="68" rx="2"/>' +
          '<path fill="' + СТАЛЬ + '" d="M0 36 L21 36 V16 L10.5 3 L0 16 Z"/>' +
          /* У валета наряд перевёрнут: куртка синяя, а пелерина красная.
             Так он отличается от старших не только шляпой, но и с первого
             взгляда на цвет — а красное пятно остаётся у всех троих. */
          плечи(СИНИЙ) + пелерина(ПЛАЩ) +
          // жабо
          '<path fill="' + СВЕТЛОЕ + '" d="M32 66 C38 73 62 73 68 66 L72 78 ' +
          'C62 86 38 86 28 78 Z"/>' +
          '<path fill="' + ДЕРЕВО + '" d="M32 44 C28 56 29 66 33 72 L41 68 ' +
          'C38 60 38 52 39 46 Z"/>' +
          '<path fill="' + ДЕРЕВО + '" d="M68 44 C72 56 71 66 67 72 L59 68 ' +
          'C62 60 62 52 61 46 Z"/>' +
          '<rect fill="' + ЛИЦО + '" x="35" y="32" width="30" height="40" rx="14"/>' +
          глаза(46) +
          // Перо крупное: на мелкой карте это второй после шляпы опознавательный знак.
          '<path fill="' + СВЕТЛОЕ + '" d="M70 28 C88 19 98 6 94 0 L72 16 Z"/>' +
          /* Шляпа вместо короны — главное отличие валета от старших:
             там, где у короля и дамы сверкает золото, у него синее сукно
             с золотой лентой. */
          '<path fill="' + СИНИЙ + '" d="M25 33 C25 15 36 8 50 8 C64 8 75 15 75 33 Z"/>' +
          '<rect fill="' + ЗОЛОТО + '" x="24" y="26" width="52" height="7" rx="2"/>' +
          '<rect fill="' + СИНИЙ + '" x="19" y="31" width="62" height="9" rx="4"/>' +
        '</g>' +
      '</symbol>'
    );
  }

  /**
   * Рубашка — то, что игрок видит чаще всего: вся колода, весь отбой,
   * все карты соперника. Поэтому она сделана по-настоящему:
   *
   *  1) узор — повторяющаяся сетка ромбов с камешком в каждой ячейке
   *     (шаг взят крупный: мелкая сетка на карте в 40 точек шириной
   *     превращается в грязную кашу);
   *  2) рамка в два уровня — светлое поле по краю, просвет, тонкий кант;
   *  3) в середине — медальон, он держит взгляд на крупной карте.
   *
   * ЦВЕТ. Настоящий цвет здесь один — цвет поля (rect с классом
   * «рубашка__фон»). Узор и канты нарисованы белым с прозрачностью, поэтому
   * они сами подстраиваются под любой цвет поля: оформителю достаточно
   * поменять одну заливку в style.css, и рубашка останется согласованной.
   */
  /* Ячейки узоров. Каждая — маленький кусочек, которым браузер замащивает
     всё поле рубашки. Ячейки нарочно крупные (30–60 единиц при ширине карты
     250): мелкий узор красив на столе и превращается в грязь в руке.

     Все узоры нарисованы БЕЛЫМ С ПРОЗРАЧНОСТЬЮ, а не своей краской.
     Поэтому любой из них ложится на любое поле и остаётся согласованным
     с его цветом — менять узор и цвет по отдельности не нужно. */
  function складУзоров() {
    return (
      // Ромбы с камешком — узор первой рубашки, «Бордо».
      '<pattern id="колода-узор-бордо" width="34" height="34" patternUnits="userSpaceOnUse" ' +
      'patternTransform="rotate(45 0 0)">' +
        '<path d="M0 0 H34 M0 0 V34" fill="none" stroke="#ffffff" stroke-opacity="0.30" stroke-width="5"/>' +
        '<path d="M17 9 L25 17 L17 25 L9 17 Z" fill="#ffffff" fill-opacity="0.22"/>' +
      '</pattern>' +
      // Шотландская клетка: широкие полосы вдоль и поперёк, между ними нитка.
      '<pattern id="колода-узор-клетка" width="52" height="52" patternUnits="userSpaceOnUse">' +
        '<rect x="0" y="0" width="52" height="16" fill="#ffffff" fill-opacity="0.20"/>' +
        '<rect x="0" y="0" width="16" height="52" fill="#ffffff" fill-opacity="0.20"/>' +
        '<rect x="0" y="0" width="16" height="16" fill="#ffffff" fill-opacity="0.16"/>' +
        '<path d="M34 0 V52 M0 34 H52" stroke="#ffffff" stroke-opacity="0.30" stroke-width="3"/>' +
      '</pattern>' +
      // Восьмиконечные звёзды вразбежку.
      '<pattern id="колода-узор-звёзды" width="54" height="54" patternUnits="userSpaceOnUse">' +
        '<path d="M13.5 0 L17.5 9.5 L27 13.5 L17.5 17.5 L13.5 27 L9.5 17.5 L0 13.5 L9.5 9.5 Z" ' +
        'fill="#ffffff" fill-opacity="0.52"/>' +
        '<path d="M40.5 27 L44.5 36.5 L54 40.5 L44.5 44.5 L40.5 54 L36.5 44.5 L27 40.5 L36.5 36.5 Z" ' +
        'fill="#ffffff" fill-opacity="0.52"/>' +
        '<circle cx="40.5" cy="13.5" r="3.5" fill="#ffffff" fill-opacity="0.26"/>' +
        '<circle cx="13.5" cy="40.5" r="3.5" fill="#ffffff" fill-opacity="0.26"/>' +
      '</pattern>' +
      // Плетёнка: ленты, ныряющие друг под друга.
      '<pattern id="колода-узор-плетёнка" width="46" height="46" patternUnits="userSpaceOnUse">' +
        '<rect x="2" y="2" width="42" height="18" rx="5" fill="#ffffff" fill-opacity="0.36"/>' +
        '<rect x="2" y="26" width="18" height="18" rx="5" fill="#ffffff" fill-opacity="0.36"/>' +
        '<rect x="26" y="26" width="18" height="18" rx="5" fill="#ffffff" fill-opacity="0.18"/>' +
      '</pattern>' +
      // Крупный горох с точкой между.
      '<pattern id="колода-узор-крапинка" width="38" height="38" patternUnits="userSpaceOnUse">' +
        '<circle cx="10" cy="10" r="9" fill="#ffffff" fill-opacity="0.40"/>' +
        '<circle cx="29" cy="29" r="9" fill="#ffffff" fill-opacity="0.40"/>' +
        '<circle cx="29" cy="10" r="3" fill="#ffffff" fill-opacity="0.24"/>' +
        '<circle cx="10" cy="29" r="3" fill="#ffffff" fill-opacity="0.24"/>' +
      '</pattern>' +
      // Узор виден только внутри внутреннего поля, за края он не вылезает.
      '<clipPath id="колода-поле-рубашки">' +
        '<rect x="16" y="16" width="218" height="318" rx="14"/>' +
      '</clipPath>'
    );
  }

  /**
   * Одна рубашка целиком: светлая кайма, цветное поле, узор, кант и середина.
   * Собрана из общих частей, чтобы шесть вариантов не разъезжались
   * по толщине рамок и отступам.
   *
   * @param {string} ключ    короткое имя варианта (идёт в класс для оформителя)
   * @param {string} цвет    цвет поля
   * @param {string} узор    какой ячейкой мостить поле ('' — без узора)
   * @param {string} середина что нарисовать в середине (медальон или вензель)
   * @param {boolean} общийКласс ставить ли класс «рубашка__фон», которым
   *        оформитель красит рубашку по умолчанию. У остальных вариантов его
   *        быть не должно: иначе одно правило в style.css перекрасило бы
   *        разом все шесть, и выбор перестал бы работать.
   */
  function однаРубашка(ключ, цвет, узор, середина, общийКласс) {
    const классПоля = (общийКласс ? 'рубашка__фон ' : '') + 'рубашка__фон--' + ключ;
    return (
      '<rect class="рубашка__поле" x="0" y="0" width="250" height="350" rx="20" fill="#f3efe4"/>' +
      '<rect class="' + классПоля + '" x="16" y="16" width="218" height="318" rx="14" ' +
      'fill="' + цвет + '"/>' +
      (узор
        ? '<g clip-path="url(#колода-поле-рубашки)">' +
          '<rect x="16" y="16" width="218" height="318" fill="url(#колода-узор-' + узор + ')"/>' +
          '</g>'
        : '') +
      '<rect x="27" y="27" width="196" height="296" rx="9" fill="none" ' +
      'stroke="#ffffff" stroke-opacity="0.45" stroke-width="3"/>' +
      середина
    );
  }

  /* Середина рубашки. Медальон-ромб держит взгляд на крупной карте,
     а у «Вензеля» она главная: там нет мелкого узора вовсе — только
     крупная золотая розетка. Такой вариант нужен тем, у кого от ряби
     в глазах рябит. */
  const МЕДАЛЬОН =
    '<g transform="translate(125 175)">' +
      '<path d="M0 -60 L44 0 L0 60 L-44 0 Z" fill="#ffffff" fill-opacity="0.16" ' +
      'stroke="#ffffff" stroke-opacity="0.5" stroke-width="3"/>' +
      '<path d="M0 -30 L22 0 L0 30 L-22 0 Z" fill="#ffffff" fill-opacity="0.28"/>' +
    '</g>';

  const РОЗЕТКА =
    '<g transform="translate(125 175)" fill="#e6b34a">' +
      '<path d="M0 -86 L20 -26 L80 -26 L32 10 L50 70 L0 34 L-50 70 L-32 10 ' +
      'L-80 -26 L-20 -26 Z" fill-opacity="0.85"/>' +
      '<circle cx="0" cy="-6" r="20" fill="#f3efe4" fill-opacity="0.9"/>' +
      '<circle cx="0" cy="-6" r="9" fill="#e6b34a"/>' +
    '</g>';

  const БЕЗ_СЕРЕДИНЫ = '';

  /**
   * Все рубашки списком, в порядке показа. Имена человеческие: человек
   * выбирает глазами, но подпись под рисунком тоже читает.
   */
  const РУБАШКИ = [
    { ключ: 'бордо', имя: 'Бордо',
      разметка: function () { return однаРубашка('бордо', '#6e2233', 'бордо', МЕДАЛЬОН, true); } },
    { ключ: 'клетка', имя: 'Клетка',
      разметка: function () { return однаРубашка('клетка', '#21467f', 'клетка', БЕЗ_СЕРЕДИНЫ, false); } },
    // У звёзд медальона нет нарочно: узор сам крупный, вдвоём они спорят.
    { ключ: 'звёзды', имя: 'Звёзды',
      разметка: function () { return однаРубашка('звёзды', '#1b2a5e', 'звёзды', БЕЗ_СЕРЕДИНЫ, false); } },
    /* Плетёнка сливовая, а не зелёная, как задумывалась: на зелёном сукне
       зелёная рубашка растворялась — карту было видно только по светлой кайме. */
    { ключ: 'плетёнка', имя: 'Плетёнка',
      разметка: function () { return однаРубашка('плетёнка', '#43286b', 'плетёнка', БЕЗ_СЕРЕДИНЫ, false); } },
    { ключ: 'вензель', имя: 'Вензель',
      разметка: function () { return однаРубашка('вензель', '#23252d', '', РОЗЕТКА, false); } },
    { ключ: 'крапинка', имя: 'Крапинка',
      разметка: function () { return однаРубашка('крапинка', '#7a4b23', 'крапинка', МЕДАЛЬОН, false); } }
  ];

  /** Какая рубашка сейчас выбрана. По умолчанию первая в списке. */
  let выбранная = РУБАШКИ[0].ключ;

  /** Найти рубашку по ключу. Незнакомый ключ — берём первую. */
  function найтиРубашку(ключ) {
    for (const р of РУБАШКИ) if (р.ключ === ключ) return р;
    return РУБАШКИ[0];
  }

  /**
   * Перерисовать общий образец рубашки.
   *
   * ЗАЧЕМ ИМЕННО ТАК. Карты в игре живут долго: у каждой теперь постоянное
   * имя, и её кусочек разметки не создаётся заново при каждой перерисовке,
   * а переезжает по столу. Значит, поменяй мы рубашку только для новых карт —
   * старые остались бы со старым рисунком до конца партии, и человек решил бы,
   * что выбор не работает.
   *
   * Поэтому все карты рубашкой вверх ссылаются на ОДИН образец
   * («колода-рубашка»), а смена варианта перерисовывает его начинку.
   * Браузер сам обновляет все ссылки разом — и колода, и отбой, и рука
   * соперника меняются в тот же миг, посреди партии.
   */
  function применитьРубашку() {
    const образец = document.getElementById('колода-рубашка');
    if (!образец) return;
    образец.innerHTML = найтиРубашку(выбранная).разметка();
  }

  function складРубашки() {
    return складУзоров() +
      // Начинку образца кладёт «применитьРубашку» — сразу после склада.
      '<symbol id="колода-рубашка" viewBox="0 0 250 350"></symbol>';
  }

  /** Один раз положить склад на страницу. Второй раз ничего не делает. */
  function поставитьСклад() {
    if (document.getElementById('колода-склад')) return;
    const обёртка = document.createElement('div');
    обёртка.innerHTML =
      '<svg id="колода-склад" xmlns="http://www.w3.org/2000/svg" ' +
      'width="0" height="0" aria-hidden="true" focusable="false" ' +
      'style="position:absolute;width:0;height:0;overflow:hidden">' +
      складМастей() + складПортретов() + складРубашки() +
      '</svg>';
    const склад = обёртка.firstElementChild;
    (document.body || document.documentElement).appendChild(склад);
    применитьРубашку();
  }

  /* ---------- Сборка карты ---------- */

  /** Ссылка на складскую деталь. */
  function деталь(номер, x, y, ширина, высота, поворот) {
    return '<use href="#' + номер + '" xlink:href="#' + номер + '" ' +
      'x="' + x + '" y="' + y + '" width="' + ширина + '" height="' + высота + '"' +
      (поворот ? ' transform="' + поворот + '"' : '') + '/>';
  }

  /** Значок масти с центром в точке. Перевёрнутый — как в нижней половине карты. */
  function значок(масть, центрX, центрY, размер, вверхНогами) {
    const номер = 'колода-' + ИМЯ_МАСТИ[масть];
    const x = центрX - размер / 2;
    const y = центрY - размер / 2;
    const поворот = вверхНогами ? 'rotate(180 ' + центрX + ' ' + центрY + ')' : '';
    return деталь(номер, x, y, размер, размер, поворот);
  }

  /**
   * Угол карты: достоинство, под ним мелкая масть.
   * В руке карты лежат внахлёст и от каждой видна узкая левая полоска —
   * именно этот угол игрок и читает, поэтому он прижат к самому краю.
   */
  function уголКарты(масть, имя) {
    /* «10» — единственное достоинство из двух знаков, и места в углу ему
       не хватает. Раньше мы просто брали кегль поменьше — и десятка выходила
       заметно мельче соседних карт: в веере углы стоят рядом, и одна мелкая
       цифра среди крупных бросалась в глаза сразу.

       Теперь высота у всех достоинств одна и та же, а два знака десятки
       СЖИМАЮТСЯ ПО ШИРИНЕ: цифры становятся узкими, но остаются такой же
       величины.

       Насколько сжимать — мерено, а не на глаз. В единицах этого холста
       (ширина карты 250) «10» без сжатия занимает 64, а свободного места
       в углу — от 8 до 60: левее начинается кант карты, правее — значки
       середины. Отсюда и числа: сжатие 0,82 и зазор между знаками −2 дают
       ширину 51, то есть цифры стоят свободно и ни на что не налезают.
       Первый заход был жёстче (0,72), и десятка выглядела сдавленной.

       Середина у двузначного достоинства сдвинута на три единицы вправо
       (34 вместо 31) — это меньше точки на живой карте, зато с левой
       стороны появляется запас, чтобы цифра не касалась канта. */
    const узкое = имя.length > 1;
    const середина = узкое ? 34 : 31;
    const сжатие = узкое
      ? ' letter-spacing="-2" transform="translate(34 0) scale(0.82 1) translate(-34 0)"'
      : '';
    return '<text x="' + середина + '" y="60" text-anchor="middle" font-size="54" ' +
      'font-family="Georgia, \'Times New Roman\', serif" font-weight="700" ' +
      'fill="currentColor"' + сжатие + '>' + имя + '</text>' +
      значок(масть, 31, 84, 30, false);
  }

  /**
   * Где стоят значки в середине — так же, как на настоящих картах.
   * Ключ — сколько значков, значение — точки по холсту 250 на 350.
   * У семёрки седьмой значок стоит между верхней парой и средней, а не
   * седьмым в столбик: именно по этому узору карту узнают не считая.
   */
  const ЛЕВО = 84;
  const ЦЕНТР = 125;
  const ПРАВО = 166;
  const ВЕРХ = 76;
  const НИЗ = 274;
  const СЕРЕДИНА = 175;

  const РАСКЛАДКИ = {
    2: [[ЦЕНТР, ВЕРХ], [ЦЕНТР, НИЗ]],
    3: [[ЦЕНТР, ВЕРХ], [ЦЕНТР, СЕРЕДИНА], [ЦЕНТР, НИЗ]],
    4: [[ЛЕВО, ВЕРХ], [ПРАВО, ВЕРХ], [ЛЕВО, НИЗ], [ПРАВО, НИЗ]],
    5: [[ЛЕВО, ВЕРХ], [ПРАВО, ВЕРХ], [ЦЕНТР, СЕРЕДИНА], [ЛЕВО, НИЗ], [ПРАВО, НИЗ]],
    6: [[ЛЕВО, ВЕРХ], [ПРАВО, ВЕРХ], [ЛЕВО, СЕРЕДИНА], [ПРАВО, СЕРЕДИНА],
        [ЛЕВО, НИЗ], [ПРАВО, НИЗ]],
    7: [[ЛЕВО, ВЕРХ], [ПРАВО, ВЕРХ], [ЦЕНТР, 125], [ЛЕВО, СЕРЕДИНА], [ПРАВО, СЕРЕДИНА],
        [ЛЕВО, НИЗ], [ПРАВО, НИЗ]],
    8: [[ЛЕВО, ВЕРХ], [ПРАВО, ВЕРХ], [ЦЕНТР, 125], [ЛЕВО, СЕРЕДИНА], [ПРАВО, СЕРЕДИНА],
        [ЦЕНТР, 225], [ЛЕВО, НИЗ], [ПРАВО, НИЗ]],
    9: [[ЛЕВО, ВЕРХ], [ПРАВО, ВЕРХ], [ЛЕВО, 142], [ПРАВО, 142], [ЦЕНТР, СЕРЕДИНА],
        [ЛЕВО, 208], [ПРАВО, 208], [ЛЕВО, НИЗ], [ПРАВО, НИЗ]],
    10: [[ЛЕВО, ВЕРХ], [ПРАВО, ВЕРХ], [ЦЕНТР, 109], [ЛЕВО, 142], [ПРАВО, 142],
         [ЛЕВО, 208], [ПРАВО, 208], [ЦЕНТР, 241], [ЛЕВО, НИЗ], [ПРАВО, НИЗ]]
  };

  /** Середина числовой карты: значки по раскладке, нижняя половина — вверх ногами. */
  function серединаЧисловой(масть, сколько) {
    const точки = РАСКЛАДКИ[сколько] || [];
    let рисунок = '';
    for (const точка of точки) {
      рисунок += значок(масть, точка[0], точка[1], 44, точка[1] > СЕРЕДИНА);
    }
    return рисунок;
  }

  /** Середина туза — одна крупная масть. */
  function серединаТуза(масть) {
    return значок(масть, ЦЕНТР, СЕРЕДИНА, 118, false);
  }

  /**
   * Середина валета, дамы, короля — как в настоящей колоде: портрет
   * в верхней половине поля и он же, перевёрнутый, в нижней. Между ними
   * тонкая черта. Смысл в том, что карту можно взять любой стороной:
   * одна из половин всегда стоит к игроку правильно.
   */
  function серединаФигуры(масть, имя) {
    const номера = {
      'В': 'колода-портрет-валет',
      'Д': 'колода-портрет-дама',
      'К': 'колода-портрет-король'
    };
    const левый = 56;
    const ширина = 138;
    const верх = 46;
    const половина = 129;      // (304 − 46) ÷ 2 — ровно половина поля
    return '<rect x="' + (левый - 2) + '" y="' + (верх - 2) + '" width="' + (ширина + 4) +
      '" height="' + (половина * 2 + 4) + '" rx="8" fill="none" ' +
      'stroke="currentColor" stroke-opacity="0.4" stroke-width="2"/>' +
      значок(масть, 74, 64, 26, false) +
      значок(масть, 176, 286, 26, true) +
      деталь(номера[имя], левый, верх, ширина, половина, '') +
      деталь(номера[имя], левый, верх, ширина, половина, 'rotate(180 125 175)') +
      '<line x1="' + левый + '" y1="175" x2="' + (левый + ширина) + '" y2="175" ' +
      'stroke="currentColor" stroke-opacity="0.5" stroke-width="2"/>';
  }

  /** Что рисуем в середине — зависит от достоинства. */
  function серединаКарты(масть, имя) {
    if (имя === 'Т') return серединаТуза(масть);
    if (имя === 'В' || имя === 'Д' || имя === 'К') return серединаФигуры(масть, имя);
    const сколько = parseInt(имя, 10);
    return серединаЧисловой(масть, сколько);
  }

  /** Готовый узел из строчки с разметкой. */
  function узелИзСтрочки(строчка) {
    const обёртка = document.createElement('div');
    обёртка.innerHTML = строчка;
    return обёртка.firstElementChild;
  }

  /** Начало любого рисунка карты. Тянется на всю карту, какого бы та ни была размера. */
  function началоХолста(класс) {
    return '<svg class="' + класс + '" xmlns="http://www.w3.org/2000/svg" ' +
      'xmlns:xlink="http://www.w3.org/1999/xlink" ' +
      'viewBox="0 0 ' + ШИРИНА + ' ' + ВЫСОТА + '" preserveAspectRatio="none" ' +
      'aria-hidden="true" focusable="false" ' +
      'style="display:block;width:100%;height:100%">';
  }

  /**
   * Лицо карты. Возвращает готовый узел <svg>.
   * Незнакомая масть или достоинство — возвращаем null: пусть игра нарисует
   * карту по-старому, это лучше пустого места.
   */
  function нарисовать(масть, имя) {
    if (!ИМЯ_МАСТИ[масть] || !имя) return null;
    поставитьСклад();
    const рисунок = началоХолста('карта-рисунок') +
      // Тонкий кант внутри карты — не в цвет масти, чтобы он не спорил
      // со значками. Фон карты рисует style.css, здесь он нарочно прозрачный.
      '<rect x="5" y="5" width="240" height="340" rx="16" fill="none" ' +
      'stroke="#0f1c2e" stroke-opacity="0.16" stroke-width="2"/>' +
      '<g fill="currentColor">' +
        уголКарты(масть, имя) +
        // Тот же угол вверх ногами в правом нижнем — как на настоящих картах.
        '<g transform="rotate(180 125 175)">' + уголКарты(масть, имя) + '</g>' +
        серединаКарты(масть, имя) +
      '</g></svg>';
    return узелИзСтрочки(рисунок);
  }

  /**
   * Карта рубашкой вверх.
   *
   * Без довода рисуется ВЫБРАННАЯ рубашка, и рисуется ссылкой на общий
   * образец — такая карта сама переоденется, когда человек сменит вариант,
   * даже посреди партии.
   *
   * С доводом («звёзды») рисуется именно этот вариант и навсегда: это
   * для экрана выбора, где шесть рубашек лежат рядом и меняться не должны.
   */
  function рубашка(ключ) {
    поставитьСклад();
    if (ключ) {
      return узелИзСтрочки(
        началоХолста('рубашка-рисунок рубашка-рисунок--образец') +
        найтиРубашку(ключ).разметка() +
        '</svg>'
      );
    }
    return узелИзСтрочки(
      началоХолста('рубашка-рисунок') +
      деталь('колода-рубашка', 0, 0, ШИРИНА, ВЫСОТА, '') +
      '</svg>'
    );
  }

  /** Список рубашек для экрана выбора: ключ и человеческое имя. */
  function рубашки() {
    return РУБАШКИ.map(function (р) { return { ключ: р.ключ, имя: р.имя }; });
  }

  /**
   * Выбрать рубашку. Возвращает true, если ключ знакомый; на незнакомом
   * ключе ничего не меняет и возвращает false — тогда остаётся прежняя.
   * Где хранить выбор, этот файл не знает: его дело — рисовать.
   */
  function выбратьРубашку(ключ) {
    let есть = false;
    for (const р of РУБАШКИ) if (р.ключ === ключ) есть = true;
    if (!есть) return false;
    выбранная = ключ;
    поставитьСклад();
    применитьРубашку();
    return true;
  }

  /** Какая рубашка выбрана сейчас. */
  function какаяРубашка() {
    return выбранная;
  }

  /**
   * Один значок масти сам по себе — для метки козыря рядом со столом.
   * Цвет тот же приём: currentColor, то есть цвет того места, куда поставили.
   */
  function значокМасти(масть) {
    if (!ИМЯ_МАСТИ[масть]) return null;
    поставитьСклад();
    return узелИзСтрочки(
      '<svg class="значок-масти" xmlns="http://www.w3.org/2000/svg" ' +
      'xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 100 100" ' +
      'aria-hidden="true" focusable="false" ' +
      'style="display:inline-block;width:1em;height:1em;vertical-align:-0.12em;fill:currentColor">' +
      деталь('колода-' + ИМЯ_МАСТИ[масть], 0, 0, 100, 100, '') +
      '</svg>'
    );
  }

  window.КолодаРисунок = {
    нарисовать: нарисовать,
    рубашка: рубашка,
    значокМасти: значокМасти,
    рубашки: рубашки,
    выбратьРубашку: выбратьРубашку,
    какаяРубашка: какаяРубашка
  };
})();
