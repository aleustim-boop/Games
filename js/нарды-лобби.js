'use strict';

/* =====================================================================
   НАРДЫ — ЛОББИ. Теперь по эталону дурака: на первом шаге (#экран-лобби)
   ровно четыре карточки-входа, второй шаг — уже существующий
   #экран-бота-нард (открывает карточка «Играть с ботом»), там вариант,
   уровень и «Играть».

   ЧЕГО ЗДЕСЬ НЕТ. Ни одного правила игры, ни одного запроса к серверу —
   этот файл только показывает лобби вместо #экран-режимов и нажимает
   за человека уже существующие кнопки — те же, что были всегда. Второй
   дороги к партии, к боту или к сети этот файл не заводит.

   ЗАПАСНОЙ ВИД. В нарды.html #экран-режимов по-прежнему помечен классом
   «экран--виден» — это ЕГО вид по умолчанию. Не загрузится этот файл
   (сбой сети, старая страница в памяти телефона) — ничего не изменится,
   страница откроется сразу на нём, и все кнопки будут работать ровно
   как до этой задачи. Загрузится — сам спрячет #экран-режимов и
   покажет #экран-лобби вместо него.

   ПОЧЕМУ ВАРИАНТ НЕ ЗАВОДИТ СВОЮ ПАМЯТЬ. У нард выбор версии уже хранится
   в localStorage под ключом «nardy_version» (см. js/нарды-экран.js,
   «прошлаяВерсия») — заводить вторую память под те же данные значит
   рано или поздно её рассинхронить. Поэтому зеркальные кнопки
   лобби-версия-… (теперь стоят на #экран-бота-нард, втором шаге) НЕ
   хранят своё состояние: они только ЗЕРКАЛЯТ состояние настоящих кнопок
   версия-… (через MutationObserver на их классах) и жмут эти настоящие
   кнопки по клику. Уровень бота своего зеркала больше не заводит вовсе:
   второй шаг показывает НАСТОЯЩИЕ кнопки уровень-…, их видимость и
   память по-прежнему считает и пишет js/нарды-экран.js.

   ПОРЯДОК ПОДКЛЮЧЕНИЯ. Этот файл стоит в нарды.html ПЕРЕД
   js/нарды-экран.js — раньше, чем тот применит запомненный выбор
   к настоящим кнопкам (это происходит на DOMContentLoaded, то есть
   заведомо позже выполнения любого обычного <script> на странице).
   Поэтому здесь нет попытки прочитать состояние один раз при запуске:
   единственный надёжный источник — сам MutationObserver, он поймает
   и то состояние, что расставит запустить() чуть позже.

   ПРОВЕРКА БЕЗ БРАУЗЕРА. Ниже, до первого обращения к document, лежит
   только чистая функция (слово при числе — не нужна нардам, но раздел
   оставлен по образцу соседних лобби для единообразия структуры файла)
   — здесь её нет, потому что у нард нет своей серии побед (см. «Мой
   счёт» в нарды.html): весь файл, кроме подключения наружу пустого
   объекта, — браузерная часть.
   ===================================================================== */

(function () {
  if (typeof document === 'undefined') return;   // Node (штабная проверка) — документа нет

  const ЭКРАН_ЛОББИ = 'экран-лобби';
  const ЭКРАН_РЕЖИМОВ = 'экран-режимов';

  const лобби = document.getElementById(ЭКРАН_ЛОББИ);
  const режимов = document.getElementById(ЭКРАН_РЕЖИМОВ);
  if (!лобби || !режимов) return;   // старая страница без этой разметки — жить нечем

  // Сигнал для js/нарды-экран.js: этот скрипт реально выполнился и разметка
  // подошла — значит у лобби сейчас есть рабочие слушатели, а не пустой
  // экран без единой кнопки-двери.
  window.НардыЛоббиЗагружено = true;

  function нажать(id) {
    const кнопка = document.getElementById(id);
    if (кнопка) кнопка.click();
  }

  /* -------------------------------------------------------------------
     ЗЕРКАЛО СОСТОЯНИЯ «Вариант»: настоящая кнопка -> кнопка второго шага.

     Пара [id настоящей кнопки на #экран-режимов, id кнопки-зеркала на
     #экран-бота-нард]. «Активна» смотрим по классу «кнопка--активная»
     (его ставит js/нарды-экран.js на версия-…) — у зеркала тот же класс,
     стиль второго шага общий с «Соперник» рядом, отдельного вида не
     заводим. У уровня бота своего зеркала больше нет: второй шаг
     показывает настоящие кнопки уровень-… напрямую.
     ------------------------------------------------------------------- */
  const ПАРЫ_ВЕРСИИ = [
    ['версия-короткие', 'лобби-версия-короткие'],
    ['версия-длинные', 'лобби-версия-длинные']
  ];

  /** Переставить класс «активна» кнопки-зеркала по настоящей паре. */
  function отразитьПару(идНастоящей, идЗеркала) {
    const настоящая = document.getElementById(идНастоящей);
    const своя = document.getElementById(идЗеркала);
    if (!настоящая || !своя) return;
    своя.classList.toggle('кнопка--активная', настоящая.classList.contains('кнопка--активная'));
  }

  function отразитьВерсию() { ПАРЫ_ВЕРСИИ.forEach(function (пара) { отразитьПару(пара[0], пара[1]); }); }

  /** Клик по кнопке-зеркалу — просто жмёт настоящую кнопку; зеркало само
   *  подтянется следом через её MutationObserver, повторно ничего не
   *  выставляем руками. */
  for (const пара of ПАРЫ_ВЕРСИИ) {
    const своя = document.getElementById(пара[1]);
    const идНастоящей = пара[0];
    if (!своя) continue;
    своя.addEventListener('click', function () { нажать(идНастоящей); });
  }

  /* Следим за настоящими кнопками: их классы меняет js/нарды-экран.js —
     и по клику человека, и один раз при запуске, применяя память
     телефона (то самое «позже», см. пояснение в шапке файла). */
  if (typeof MutationObserver === 'function') {
    const сторожВерсии = new MutationObserver(отразитьВерсию);
    for (const пара of ПАРЫ_ВЕРСИИ) {
      const узел = document.getElementById(пара[0]);
      if (узел) сторожВерсии.observe(узел, { attributes: true, attributeFilter: ['class'] });
    }
  }
  // Разметка стартует с теми же классами по умолчанию, что и в HTML —
  // отражаем их сразу, не дожидаясь первого изменения.
  отразитьВерсию();

  /* ---------- Карточка профиля ----------
     У нард нет своего модуля рекордов (в отличие от шашек и шахмат) —
     обновлять здесь нечего, кроме имени (строка «Мой счёт» в разметке
     статична, нарды.html) и фото. */

  /* Фото профиля в кружке аватара лобби — тот же приём, что у дурака
     (см. «освежитьАватар» в js/дурак-путь.js), шашек и шахмат (их
     js/шашки-лобби.js и js/шахматы-лобби.js): единственная дверь —
     window.Телеграм.фотоИгрока(), картинка грузится втихую через
     new Image(), и класс-переменную красим только в её onload —
     иначе битый адрес показал бы пустой кружок вместо нарисованного
     человечка. Память последнего подтверждённого адреса — чтобы
     не перегружать одну и ту же картинку при каждом показе лобби.
     Своего id у узла нет (в нарды.html — просто класс «аватар»
     внутри кнопки «лобби-профиль»), поэтому ищем его querySelector'ом. */
  let последнийЗагруженныйАдресАватара = '';
  function освежитьАватар() {
    const узелАватара = document.querySelector('#лобби-профиль .аватар');
    if (!узелАватара) return;
    const адрес = String((window.Телеграм && typeof window.Телеграм.фотоИгрока === 'function'
      ? window.Телеграм.фотоИгрока() : '') || '');
    if (!адрес) {
      узелАватара.classList.remove('аватар--фото');
      узелАватара.style.removeProperty('--фото-аватара');
      return;
    }
    const показатьЗагруженное = function () {
      узелАватара.style.setProperty('--фото-аватара', 'url("' + адрес + '")');
      const принялось = узелАватара.style.getPropertyValue('--фото-аватара').trim() !== '';
      if (!принялось) {
        узелАватара.classList.remove('аватар--фото');
        узелАватара.style.removeProperty('--фото-аватара');
        return;
      }
      узелАватара.classList.add('аватар--фото');
    };
    if (адрес === последнийЗагруженныйАдресАватара) {
      показатьЗагруженное();
      return;
    }
    const картинка = new Image();
    картинка.onload = function () {
      последнийЗагруженныйАдресАватара = адрес;
      // Лобби могли уже закрыть, пока шла загрузка — красить нечего.
      if (!document.body.contains(узелАватара)) return;
      показатьЗагруженное();
    };
    картинка.onerror = function () { /* сеть подвела — молча оставляем человечка */ };
    картинка.src = адрес;
  }

  function освежитьПрофиль() {
    const имя = document.getElementById('лобби-имя');
    if (имя) {
      const изTelegram = window.Телеграм && typeof window.Телеграм.имяИгрока === 'function'
        ? String(window.Телеграм.имяИгрока() || '').trim() : '';
      имя.textContent = изTelegram || 'Вы';
    }
    освежитьАватар();
  }
  освежитьПрофиль();
  // Официальный скрипт Telegram подключён с «defer» и может ответить
  // позже, чем выполнился этот файл — тот же приём, что у соседних лобби.
  try { window.addEventListener('load', освежитьПрофиль); } catch (ошибка) { /* нет окна — освежать нечего */ }

  /* Профиль освежаем ещё и каждый раз, когда лобби становится видимым, —
     тем же приёмом, что у шахмат (js/шахматы-лобби.js) и шашек
     (js/шашки-лобби.js). У нард своей публичной двери показа лобби
     наружу тоже нет: «В меню» и возврат из «Как играть»/«Оформления»
     (см. «вМеню» и «вернутьсяИзСлужебного» в js/нарды-экран.js)
     переключают класс «экран--виден» у #экран-лобби НАПРЯМУЮ, минуя
     функцию показатьЛобби ниже, — тот файл о существовании
     освежитьПрофиль не знает и знать не должен (граница между файлами).
     Поэтому сторожим сам класс: как только лобби становится видимым,
     откуда бы показ ни пришёл, имя и фото обновляются. */
  if (typeof MutationObserver === 'function') {
    const сторожЛобби = new MutationObserver(function () {
      if (лобби.classList.contains('экран--виден')) освежитьПрофиль();
    });
    сторожЛобби.observe(лобби, { attributes: true, attributeFilter: ['class'] });
  }

  const кнопкаПрофиль = document.getElementById('лобби-профиль');
  if (кнопкаПрофиль) {
    кнопкаПрофиль.addEventListener('click', function () {
      if (window.ЭкранРейтинга) window.ЭкранРейтинга.открытьСчёт('нарды');
    });
  }

  /* ---------- Показ лобби вместо экрана режимов ---------- */

  function показатьЛобби() {
    режимов.classList.remove('экран--виден');
    лобби.classList.add('экран--виден');
    освежитьПрофиль();   // на случай если Telegram ответил уже после запуска
  }
  показатьЛобби();   // главный экран страницы — лобби, а не «С кем играть»

  /* ---------- Карточки входов: переходники на уже существующие кнопки ----------
     Ни одна не заводит новую дорогу к партии, к боту или к сети — только
     нажимает узел, который уже слушает js/нарды-экран.js или js/сеть.js. */

  /* «Играть с ботом» ведёт теперь не сразу на стол, а на второй шаг —
     жмёт «кнопка-режим-бот» (показывает #экран-бота-нард). */
  const кнопкаБоты = document.getElementById('лобби-боты');
  if (кнопкаБоты) кнопкаБоты.addEventListener('click', function () { нажать('кнопка-режим-бот'); });

  /* «Играть онлайн» своего слушателя здесь не заводит: узел «лобби-найти-
     игру» находит и открывает сам js/открытые-столы.js (общий с дураком
     и шашками) — второй дороги к его двери не заводим. */

  /* «Поделиться приложением» — как у дурака: зовёт не за стол, а в само
     приложение, дверь window.Сеть.пригласитьВПриложение из общего
     js/похвастаться.js. Ответ на секунду показываем в подписи карточки,
     тот же приём, что «пригласитьДрузей» в js/дурак-путь.js. */
  const ЖДЁМ_ПРИГЛАШЕНИЕ = 6000;
  const ВЕСТЬ_ДЕРЖИТСЯ = 2500;
  let приглашениеИдёт = false;

  function словаОПриглашении(ответ) {
    if (ответ && ответ.отправлено === true) return 'Отправлено';
    if (ответ && ответ.способ === 'буфер') return 'Ссылка скопирована';
    if (ответ && ответ.способ === 'чат') return 'Выбираем чат…';
    return 'Не вышло — попробуйте ещё раз';
  }

  function пригласитьДрузей() {
    if (приглашениеИдёт) return;
    if (!window.Сеть || typeof window.Сеть.пригласитьВПриложение !== 'function') return;
    const карточка = document.getElementById('лобби-друзья');
    const подпись = карточка ? карточка.querySelector('.карточка-входа__подпись') : null;
    const исходнаяПодпись = подпись ? подпись.textContent : '';
    приглашениеИдёт = true;
    let ответили = false;
    const принять = function (ответ) {
      if (ответили) return;
      ответили = true;
      приглашениеИдёт = false;
      if (!подпись) return;
      подпись.textContent = словаОПриглашении(ответ);
      setTimeout(function () { подпись.textContent = исходнаяПодпись; }, ВЕСТЬ_ДЕРЖИТСЯ);
    };
    Promise.resolve()
      .then(function () { return window.Сеть.пригласитьВПриложение(); })
      .then(принять, function () { принять(null); });
    setTimeout(function () { принять(null); }, ЖДЁМ_ПРИГЛАШЕНИЕ);
  }

  const кнопкаДрузья = document.getElementById('лобби-друзья');
  if (кнопкаДрузья) кнопкаДрузья.addEventListener('click', пригласитьДрузей);

  /* «Вдвоём на этом устройстве» — теперь полноценная карточка сразу на
     первом шаге, между «с ботом» и «друзьями» (раньше была мелкая кнопка
     под тройкой карточек — владелец пожаловался, что спрятанную на
     втором шаге бота было не найти, потом попросил вид карточки).
     Жмёт уже существующую «кнопка-вдвоём» на запасном #экран-режимов —
     её слушает js/нарды-экран.js (начатьПартию('вдвоём')), второй дороги
     к партии не заводим. Кнопка «кнопка-бот-вдвоём» на втором шаге навсегда
     спрятана классом «скрыт» (см. нарды.html) — человеку её не видно и не
     нажать, для него путь «вдвоём» остался один; сам узел с обработчиком
     в js/нарды-экран.js оставлен, чтобы не трогать чужой файл (см.
     пояснение в нарды.html рядом с узлом). */
  const кнопкаВдвоём = document.getElementById('лобби-вдвоём');
  if (кнопкаВдвоём) кнопкаВдвоём.addEventListener('click', function () { нажать('кнопка-вдвоём'); });

  /* «Есть код? Войти» в лобби больше нет — как у дурака, он внутри
     экрана «Играть онлайн» (js/открытые-столы.js). */

  /* ---------- Верхняя строка лобби: переходники на кнопки режимов ----------
     «‹» и «⋯» у лобби свои узлы (id другой — «кнопка-назад» уже занят
     кнопкой на #экран-режимов), но слушать им нечего своего: они просто
     нажимают уже существующие кнопки и получают то же поведение —
     «кнопка-назад» ведёт на витрину (js/нарды-экран.js, уйтиНаВитрину),
     «кнопка-игра-ещё» открывает общий лист «⋯» (его слушает js/лист-ещё.js
     по списку «идОткрывающих» в js/нарды-экран.js). */
  const кнопкаНазад = document.getElementById('кнопка-лобби-назад');
  if (кнопкаНазад) кнопкаНазад.addEventListener('click', function () { нажать('кнопка-назад'); });

  /* «⋯» на лобби своего слушателя не заводит — js/лист-ещё.js открывает лист
     по её id напрямую. */

  /* ---------- Второй шаг (#экран-бота-нард): зеркало «Вариант» и «‹» ----------
     Оба узла в HTML стоят скрытыми классом «скрыт» — на запасном пути
     (этот файл не загрузился) их как не было, дублировать уже сделанный
     на #экран-режимов выбор нерабочими кнопками незачем. Открываем их
     здесь же, раз скрипт реально выполнился. */
  const блокВариантаБота = document.getElementById('блок-вариант-бота');
  if (блокВариантаБота) блокВариантаБота.classList.remove('скрыт');

  const верхБотаНард = document.getElementById('верх-бота-нард');
  if (верхБотаНард) верхБотаНард.classList.remove('скрыт');

  /* Верхняя «‹» второго шага ведёт в лобби через ту же публичную дверь,
     что использует сеть для возврата в меню (window.НардыЭкран —
     js/нарды-экран.js), — второй способ показать лобби напрямую не
     изобретаем. Системная стрелка Telegram сюда уже ведёт сама, без
     этой кнопки (шагНазад → уйтиВМеню → вМеню в js/нарды-экран.js). */
  const кнопкаБотаНазад = document.getElementById('кнопка-бота-нард-назад');
  if (кнопкаБотаНазад) {
    кнопкаБотаНазад.addEventListener('click', function () {
      if (window.НардыЭкран && typeof window.НардыЭкран.показатьПоИмени === 'function') {
        window.НардыЭкран.показатьПоИмени('экран-меню');
      }
    });
  }

  /* Наружу отдавать нечего: у нард нет ни своей памяти, ни чистых функций,
     которые стоило бы проверять без браузера (в отличие от шашек и
     шахмат — там серия побед и уровень с новым ключом памяти). */
})();
