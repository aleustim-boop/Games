/* =====================================================================
   Пульс: тихий стук браузера «я сейчас в игре» — для онлайн-дашборда штаба.

   Как это работает. Пока вкладка с игрой открыта и видна, раз в минуту
   уходит POST /пульс {initData, игра} на сервер комнат. Свернул Telegram
   или переключился на другую вкладку — молчим совсем: незачем тратить
   заряд и трафик ради того, во что человек прямо сейчас не играет.

   Подпись Telegram (initData) — единственный способ сервера узнать, кто
   играет. Нет подписи (игра открыта прямо в браузере с диска, не через
   Telegram) — стучаться незачем, сервер такой пульс всё равно не примет.

   Файл ничего не рисует и ничего не решает про правила игр — он умеет
   ровно одно дело и наружу отдаёт одну дверь: window.Пульс.запустить(игра).

   Подключение — одной строкой, без вызова из чужого js:
       <script src="js/пульс.js?v=1" data-igra="дурак" defer></script>
   Имя атрибута — латиницей: кириллица в dataset ненадёжна в части
   браузеров и может не прочитаться молча. Значение — само слово игры,
   по-русски, как договорено с сервером. Ручной window.Пульс.запустить(игра)
   по-прежнему работает — самозапуск его не отменяет и не мешает ему.
   ===================================================================== */

'use strict';

(function () {

  /* document.currentScript годится только пока этот файл выполняется
     синхронно — это верно и при defer (он лишь откладывает СТАРТ, а не
     дробит выполнение), но перестаёт работать из таймера или обработчика
     события. Поэтому читаем тег сразу, самой первой строкой исполнения. */
  const ТЕГ_ЭТОГО_СКРИПТА = document.currentScript;

  const ДОПУСТИМЫЕ_ИГРЫ = ['дурак', 'шашки', 'нарды', 'шахматы'];
  const ПЕРИОД_ПУЛЬСА = 60 * 1000;   // как часто напоминаем о себе, пока вкладка видна

  let таймер = null;      // идущий setInterval или null, если сейчас он не нужен
  let играТекущая = '';   // во что играем на этой странице — приходит в запустить()
  let запущен = false;    // Пульс.запустить() уже вызывали — второй раз не начинаем заново

  /**
   * Адрес сервера комнат. Первым делом спрашиваем готовое у js/сеть.js —
   * там уже решён спор «адрес из ссылки или вписанный человеком руками».
   * Сеть.js мог ещё не подключиться к странице (порядок подключения решает
   * штаб, не этот файл) — тогда сами читаем тот же хвостик ссылки
   * «?сервер=» или «?server=», которым пользуется и он.
   */
  function адресСервера() {
    try {
      if (window.Сеть && typeof window.Сеть.адрес === 'function') {
        const готовый = window.Сеть.адрес();
        if (готовый) return готовый;
      }
    } catch (сбой) {
      /* сеть.js подключён, но что-то в нём упало — пробуем сами ниже */
    }
    try {
      const разбор = new URLSearchParams(window.location.search);
      return разбор.get('сервер') || разбор.get('server') || '';
    } catch (сбой) {
      return '';
    }
  }

  /** Подпись Telegram, по которой сервер узнаёт игрока. Нет подписи — нет пульса. */
  function initData() {
    try {
      return String((window.Telegram && window.Telegram.WebApp && window.Telegram.WebApp.initData) || '');
    } catch (сбой) {
      return '';
    }
  }

  /**
   * Один тихий стук в сервер. Любая беда по дороге — молчим: пульс не
   * должен мешать игре и не должен засорять консоль игрока.
   */
  function стукнуть() {
    const подпись = initData();
    if (!подпись) return;
    const адрес = адресСервера();
    if (!адрес) return;
    try {
      fetch(адрес.replace(/\/+$/, '') + '/пульс', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ initData: подпись, игра: играТекущая }),
        keepalive: true
      }).catch(function () { /* сервер не ответил — не беда, стукнём через минуту */ });
    } catch (сбой) {
      /* fetch недоступен или бросил сразу же — тоже не беда */
    }
  }

  /**
   * Свериться с видимостью вкладки: видна — таймер идёт (и стучим сразу же),
   * скрыта — таймер стоит совсем. Повторный запуск таймера, пока он уже
   * идёт, не делаем: событие видимости может прийти, когда он и так тикает.
   */
  function сверитьсяСВидимостью() {
    const видна = document.visibilityState === 'visible';
    if (видна) {
      if (таймер) return;
      стукнуть();
      таймер = setInterval(стукнуть, ПЕРИОД_ПУЛЬСА);
    } else if (таймер) {
      clearInterval(таймер);
      таймер = null;
    }
  }

  document.addEventListener('visibilitychange', сверитьсяСВидимостью);

  /**
   * Начать напоминать о себе, пока страница открыта.
   * игра — одно из: 'дурак', 'шашки', 'нарды', 'шахматы'.
   * Повторный вызов (например, самозапуск и следом ручной вызов той же
   * страницей) не создаёт второй таймер — просто ничего не делает.
   */
  function запустить(игра) {
    if (запущен) return;
    запущен = true;
    играТекущая = String(игра || '');
    сверитьсяСВидимостью();
  }

  window.Пульс = { запустить: запустить };

  /* Самозапуск по data-igra из своего тега <script>. Игра не входит
     в известный набор (опечатка, пустой атрибут, чужое слово) — молчим:
     лучше отсутствие пульса, чем мусор в сервере посещений. */
  const играИзТега = ТЕГ_ЭТОГО_СКРИПТА && ТЕГ_ЭТОГО_СКРИПТА.dataset
    ? String(ТЕГ_ЭТОГО_СКРИПТА.dataset.igra || '') : '';
  if (ДОПУСТИМЫЕ_ИГРЫ.indexOf(играИзТега) !== -1) запустить(играИзТега);

})();
