'use strict';

/* =====================================================================
   НАРДЫ ПО СЕТИ — МОСТ МЕЖДУ ДОСКОЙ И ОБЩИМ ФАЙЛОМ СВЯЗИ.

   Устройство целиком повторяет js/шашки-сеть.js — нарочно: двух разных
   мостов в проекте быть не должно, иначе починка в одном не доедет
   до другого.

   Разговор с сервером ведёт js/сеть.js — один файл на все игры сборника.
   Он знает про коды комнат, пропуска и длинный опрос; про нарды не знает
   ничего. Доску рисует js/нарды-экран.js — он не знает ничего про сеть.
   Между ними стоит этот файл, и в нём нет ни правил нард, ни запросов
   к серверу.

   Двери наружу — те же, что у дурака и шашек (js/сеть.js зовёт их не
   глядя, в какую игру играют):

       window.ИграПоСети = { начать, показатьВид, показатьСвязь,
                             экран, вМеню, идёт }

   Обратно, от доски к серверу, уходят три сообщения — ровно те, что
   принимает дверь «/ход» в server/игры/нарды.js:

       { действие: 'бросить' }
       { действие: 'ход', шаги: [{ откуда, куда, кубик }] }   // пустой список = пропуск
       { действие: 'сдаться' }

   Кубики бросает сервер, ход он проверяет теми же правилами — присланному
   он не верит никогда.

   ПОЧЕМУ МОСТ ПОДКЛЮЧАЕТСЯ РАНЬШЕ js/сеть.js. Тот в конце своего файла
   сразу берётся за дело и может немедленно открыть экран — например,
   когда человек пришёл по ссылке-приглашению. Зовёт он для этого мост.
   Не будь моста к той секунде, приглашение открыло бы пустоту.
   ===================================================================== */

(function () {
  /* Имена экранов, которыми говорит js/сеть.js, — дураковы. Три из них
     на странице нард называются так же («экран-друга», «экран-комнаты»,
     «экран-входа» — их разметка скопирована из шашек без переименований),
     а «экран-меню» и «экран-игры» переводит сам экран нард
     (НардыЭкран.показатьПоИмени). Нам здесь нужно знать одно: доска это
     или уже не доска. */
  var ИМЯ_ДОСКИ = 'экран-игры';

  /* Пять имён — весь словарь js/сеть.js. Больше он ничего не просит.

     ЗАЧЕМ ЗДЕСЬ СПИСОК, А НЕ «показать что попало». В дверь «экран»
     стучится не только сеть: общие экраны сборника (рейтинг игроков,
     «Как я играю») уходя показывают тот экран, с которого их открыли, —
     и зовут для этого тот же window.ИграПоСети.экран. Имена у них свои
     («экран-лобби»), и стрелку «Назад» они возвращают себе сами
     (js/telegram.js, вернутьПрежнююСтрелку).

     А экран нард на каждый показ ставит стрелку заново. Пропусти мы
     чужое имя внутрь — стрелка получила бы лишний слой, и первое
     нажатие после рейтинга уходило бы впустую: человек жмёт «назад»
     на лобби, а со страницы не уходит (поймано проверкой
     tests/лобби-нард.js, шаг 7). Поэтому чужое имя мы показываем сами,
     ровно так же, как это делал сам рейтинг до появления моста. */
  var ИМЕНА_СЕТИ = {
    'экран-меню': true, 'экран-игры': true,
    'экран-друга': true, 'экран-комнаты': true, 'экран-входа': true
  };

  /* Сколько миллисекунд «Сдаться» ждёт второго нажатия. То же число,
     что у шашек и шахмат: сдача — решение, которое нельзя отдать
     случайному тапу. */
  var ВРЕМЯ_ПОДТВЕРЖДЕНИЯ_СДАЧИ = 5000;

  /* Идёт ли сейчас партия по сети. Спрашивают и js/сеть.js, и доска. */
  var вПартии = false;

  /* Взведена ли «Сдаться» — ждёт ли она второго нажатия. */
  var сдачаВзведена = false;
  var таймерПодтвержденияСдачи = null;

  /** Доска. Появляется в конце страницы, поэтому спрашиваем каждый раз. */
  function доска() {
    return window.НардыЭкран || null;
  }

  /** Полный файл связи (не путать с огрызком, который кладёт «похвастаться»). */
  function связь() {
    var сеть = window.Сеть;
    return сеть && typeof сеть.отправитьХод === 'function' ? сеть : null;
  }

  /* -------------------------------------------------------------------
     Что зовёт js/сеть.js
     ------------------------------------------------------------------- */

  /** За стол сели двое — партия пошла. */
  function начать() {
    вПартии = true;
    var экранДоски = доска();
    /* Отдельной команды «покажи доску» здесь нет нарочно: экран нард
       показывает её сам, когда включает сетевой режим. */
    if (экранДоски) экранДоски.включитьСеть(отправитьХод);
    освежитьКнопкуСдачи(null);
  }

  /**
   * Новое состояние стола. Всё, что здесь делается, — передаём доске:
   * решать, что нарисовать и как показать чужой ход, — её работа.
   */
  function показатьВид(вид) {
    if (!вид) return;
    вПартии = true;
    var экранДоски = доска();
    if (!экранДоски) return;
    экранДоски.включитьСеть(отправитьХод);   // повторный вызов ничего не портит
    экранДоски.показатьСетевойВид(вид);
    освежитьКнопкуСдачи(вид);
  }

  /**
   * Строка над доской: жив ли друг и жива ли связь. Слова приходят готовые
   * из js/сеть.js, вид — 'тревога', 'ожидание' или пусто. Пустой текст
   * прячет строку целиком.
   */
  function показатьСвязь(текст, вид) {
    var строка = document.getElementById('строка-связи');
    if (!строка) return;
    строка.textContent = текст || '';
    строка.classList.toggle('скрыт', !текст);
    строка.classList.toggle('связь--тревога', вид === 'тревога');
    строка.classList.toggle('связь--ожидание', вид === 'ожидание');
  }

  /** Сеть просит показать экран. Перевод имён — работа экрана нард. */
  function экран(имя) {
    /* Уходим с доски — значит, сетевая партия для нас кончилась: дальше
       человек или сидит в комнате, или выбирает соперника заново. */
    if (имя !== ИМЯ_ДОСКИ) отпуститьДоску();
    if (!ИМЕНА_СЕТИ[имя]) { показатьЧужойЭкран(имя); return; }
    var экранДоски = доска();
    if (экранДоски) экранДоски.показатьПоИмени(имя);
  }

  /**
   * Показать экран, о котором сеть не просила (см. ИМЕНА_СЕТИ выше):
   * это общий экран сборника вернулся туда, откуда его открыли. Делаем
   * ровно одно — переключаем видимый экран; стрелку «Назад» звавший
   * возвращает себе сам.
   */
  function показатьЧужойЭкран(имя) {
    var экраны = document.querySelectorAll('.экран');
    for (var к = 0; к < экраны.length; к++) {
      экраны[к].classList.toggle('экран--виден', экраны[к].id === имя);
    }
  }

  /** Сеть закрыла партию (комната пропала, вышли сами). */
  function вМеню() {
    отпуститьДоску();
    var экранДоски = доска();
    /* «экран-меню» — дураково имя; на странице нард экран сам переводит
       его в лобби (НардыЭкран.показатьПоИмени). */
    if (экранДоски) экранДоски.показатьПоИмени('экран-меню');
  }

  /**
   * «Назад» с экрана «Вход по коду» (js/сеть.js, назадСоВхода). Вход по
   * коду в нардах открывается только из лобби строкой «Есть код? Войти»,
   * поэтому и назад — снова в лобби, а не на старый экран «Играть
   * с другом» (запасной путь js/сеть.js). Тот же путь, что и вМеню():
   * «экран-меню» экран нард сам переводит в лобби.
   */
  function назадСоВхода() {
    отпуститьДоску();
    var экранДоски = доска();
    if (экранДоски) экранДоски.показатьПоИмени('экран-меню');
  }

  /** Вернуть доску в обычное состояние: дальше играем с ботом или вдвоём. */
  function отпуститьДоску() {
    if (!вПартии) return;
    вПартии = false;
    показатьСвязь('');
    освежитьКнопкуСдачи(null);
    var экранДоски = доска();
    if (экранДоски) экранДоски.выключитьСеть();
  }

  /* -------------------------------------------------------------------
     Что зовёт доска
     ------------------------------------------------------------------- */

  /**
   * Собрать сообщение для сервера поле за полем.
   *
   * Переписываем руками, а не пересылаем как есть: на доске в тех же
   * перемещениях лежат имена шашек и прочая внутренняя мелочь, и серверу
   * её знать незачем. Незнакомое действие не отправляем вовсе — пусть
   * лучше человек прочтёт отказ, чем сервер разберёт непонятное.
   */
  function собратьСообщение(сообщение) {
    var действие = сообщение && сообщение.действие;
    if (действие === 'бросить' || действие === 'сдаться') {
      return { действие: действие };
    }
    if (действие === 'ход') {
      var шаги = Array.isArray(сообщение.шаги) ? сообщение.шаги : [];
      return {
        действие: 'ход',
        шаги: шаги.map(function (шаг) {
          return { откуда: шаг.откуда, куда: шаг.куда, кубик: шаг.кубик };
        })
      };
    }
    return null;
  }

  /**
   * Отправить сообщение доски серверу. Обещание никогда не срывается:
   * при любой беде вернётся отказ с причиной, которую доска покажет
   * человеку словами (см. «отправитьВСеть» в js/нарды-экран.js — она
   * принимает и обещание, и готовый ответ).
   */
  function отправитьХод(сообщение) {
    var намерение = собратьСообщение(сообщение);
    if (!намерение) {
      return Promise.resolve({
        принято: false,
        причина: 'Это действие игре по сети неизвестно'
      });
    }
    var сеть = связь();
    if (!сеть) {
      return Promise.resolve({
        принято: false,
        причина: 'Игра по сети не загрузилась — обновите страницу'
      });
    }
    return сеть.отправитьХод(намерение).then(function (ответ) {
      /* Пустой ответ приходит, когда человек успел выйти из партии:
         тогда показывать нечего, и молчание тут — правильный ответ. */
      if (!ответ) return { принято: false, тихо: true };
      if (ответ.ошибкаСвязи) {
        return { принято: false, причина: 'Связь с игрой потеряна — ход не ушёл' };
      }
      return ответ;
    }).catch(function () {
      return { принято: false, причина: 'Ход не удалось отправить' };
    });
  }

  /* -------------------------------------------------------------------
     КНОПКА «СДАТЬСЯ»

     Обработчик висит здесь, а не на экране нард, по одной причине:
     сдаваться в нардах можно только по сети (с ботом для этого есть
     «В меню»), а всё сетевое на этой странице собрано в мосту. Дверь
     самого действия — НардыЭкран.сдаться(): решает исход сервер, мы
     только просим.

     Подтверждение вторым нажатием — тот же приём, что у шашек
     (js/шашки-экран.js, «взвестиСдачу»): первый тап меняет надпись на
     «Да, сдаюсь», второй по той же кнопке отправляет сдачу; не нажали —
     кнопка сама возвращается в обычный вид.

     Вне сетевой партии кнопки на странице нет вовсе (класс «скрыт»):
     мёртвых кнопок в сборнике не бывает.
     ------------------------------------------------------------------- */

  function кнопкаСдачи() {
    return document.getElementById('кнопка-сдаться');
  }

  function взвестиСдачу() {
    var кнопка = кнопкаСдачи();
    if (!кнопка || сдачаВзведена) return;
    сдачаВзведена = true;
    кнопка.textContent = 'Да, сдаюсь';
    кнопка.classList.add('кнопка-сдаться--подтверждение');
    clearTimeout(таймерПодтвержденияСдачи);
    таймерПодтвержденияСдачи = setTimeout(разоружитьСдачу, ВРЕМЯ_ПОДТВЕРЖДЕНИЯ_СДАЧИ);
  }

  function разоружитьСдачу() {
    сдачаВзведена = false;
    clearTimeout(таймерПодтвержденияСдачи);
    таймерПодтвержденияСдачи = null;
    var кнопка = кнопкаСдачи();
    if (!кнопка) return;
    кнопка.textContent = 'Сдаться';
    кнопка.classList.remove('кнопка-сдаться--подтверждение');
  }

  /** Клик по «Сдаться»: первый тап взводит, второй подтверждает. */
  function нажалиСдаться(событие) {
    /* Иначе тот же тап долетит до документа и тут же разоружит кнопку. */
    if (событие && typeof событие.stopPropagation === 'function') событие.stopPropagation();
    if (!вПартии) return;
    if (!сдачаВзведена) { взвестиСдачу(); return; }
    разоружитьСдачу();
    var экранДоски = доска();
    if (экранДоски && typeof экранДоски.сдаться === 'function') экранДоски.сдаться();
  }

  /**
   * Показать или спрятать «Сдаться». Вид партии (или null, когда его ещё
   * нет) — единственный источник слова «партия кончилась»: доска про
   * сдачу соперника не знает вовсе.
   */
  function освежитьКнопкуСдачи(вид) {
    var кнопка = кнопкаСдачи();
    if (!кнопка) return;
    var можно = вПартии && !(вид && вид.завершена);
    кнопка.classList.toggle('скрыт', !можно);
    кнопка.disabled = !можно;
    if (!можно) разоружитьСдачу();
  }

  function подключитьКнопкуСдачи() {
    var кнопка = кнопкаСдачи();
    if (!кнопка) return;
    кнопка.addEventListener('click', нажалиСдаться);
    /* Тап в любое другое место экрана снимает взведённую кнопку —
       передумать должно быть так же легко, как нажать. */
    document.addEventListener('click', function () {
      if (сдачаВзведена) разоружитьСдачу();
    });
    освежитьКнопкуСдачи(null);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', подключитьКнопкуСдачи);
  } else {
    подключитьКнопкуСдачи();
  }

  window.ИграПоСети = {
    начать: начать,
    показатьВид: показатьВид,
    показатьСвязь: показатьСвязь,
    экран: экран,
    вМеню: вМеню,
    назадСоВхода: назадСоВхода,
    идёт: function () { return вПартии; }
  };

  /* Наружу — только для доски: ей надо знать, идёт ли сетевая партия,
     когда человек уходит со страницы или начинает партию с ботом. */
  window.НардыСеть = {
    идёт: function () { return вПартии; },
    покинуть: function () {
      var сеть = связь();
      отпуститьДоску();
      if (сеть && typeof сеть.покинутьПартию === 'function') сеть.покинутьПартию();
    }
  };
})();
