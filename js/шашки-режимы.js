'use strict';

/* =====================================================================
   ШАШКИ — С КЕМ ИГРАТЬ. Переключение экранов выбора.

   Входов три, как и просил владелец («как в дураке»):
     • с ботом — уровень спрашиваем на своём экране, там же «Играть»;
     • вдвоём на этом устройстве — начинается сразу, настраивать нечего;
     • с другом онлайн — игра по сети: код стола, вход по коду. Эти экраны
       ведёт общий js/сеть.js через мост js/шашки-сеть.js, а этот файл
       только держит список экранов и показывает нужный.

   ЧЕГО ЗДЕСЬ НЕТ. Ни одного правила игры и ни одной партии. Этот файл
   только показывает и прячет секции страницы. Партии начинает
   js/шашки-экран.js — он слушает те же две кнопки («Играть» на экране
   бота и «Играть вдвоём») своими руками. Два слушателя на одной кнопке
   не мешают друг другу: один заводит партию, второй меняет экран.

   Так разделено нарочно. Экрану игры не нужно знать, сколько на странице
   экранов выбора и как они называются, а этому файлу — не нужно знать,
   что такое дамка. Разойтись им негде.

   Наружу: window.ШашкиРежимы = { показать, показатьДоску, открыты }.
   «открыты()» спрашивает стрелка «Назад» в js/шашки-телеграм.js, чтобы
   отматывать по одному шагу: сначала закрыть открытое поверх доски,
   потом с доски — в меню, и только из меню — на витрину игр.
   ===================================================================== */

(function () {
  /* Все переключаемые экраны одним списком: показать один — значит
     спрятать остальные. Имена трёх последних дураковы — их знает общий
     js/сеть.js, который эти экраны и заполняет.
     Доска стоит последней нарочно: всё, что до неё, — это «ещё не играем». */
  var ИМЕНА_ЭКРАНОВ = [
    'экран-режимов',      // с кем играть
    'экран-бота-шашек',   // уровень бота
    'экран-друга',        // игра по сети: создать или войти
    'экран-комнаты',      // код стола, ждём друга
    'экран-входа',        // вход по коду
    'экран-шашек'         // доска
  ];

  var экраны = {};
  for (var i = 0; i < ИМЕНА_ЭКРАНОВ.length; i++) {
    экраны[ИМЕНА_ЭКРАНОВ[i]] = document.getElementById(ИМЕНА_ЭКРАНОВ[i]);
  }
  var экранИтога = document.getElementById('экран-итога');

  /** Показать ровно один экран из списка, остальные спрятать. */
  function показатьПоИмени(имя) {
    if (!экраны[имя]) {
      console.warn('Шашки: не нашёл экран «' + имя + '» — показывать нечего');
      return;
    }
    for (var к = 0; к < ИМЕНА_ЭКРАНОВ.length; к++) {
      var экран = экраны[ИМЕНА_ЭКРАНОВ[к]];
      if (экран) экран.classList.toggle('экран--виден', ИМЕНА_ЭКРАНОВ[к] === имя);
    }
    /* Плашка итога лежит поверх доски. Уходя с доски, её надо убрать:
       иначе она висела бы поверх выбора соперника и закрывала кнопки. */
    if (имя !== 'экран-шашек' && экранИтога) экранИтога.classList.remove('экран--виден');
  }

  /** Первый экран: с кем играть. */
  function показать() {
    показатьПоИмени('экран-режимов');
  }

  /** Доска. Зовут отсюда же — с кнопок, которые начинают партию. */
  function показатьДоску() {
    показатьПоИмени('экран-шашек');
  }

  /** Открыт ли сейчас какой-нибудь экран, кроме доски. */
  function открыты() {
    var открыт = какойОткрыт();
    return !!открыт && открыт !== 'экран-шашек';
  }

  /** Имя открытого сейчас экрана — или пустая строка, если не открыт ни один. */
  function какойОткрыт() {
    for (var к = 0; к < ИМЕНА_ЭКРАНОВ.length; к++) {
      if (видим(экраны[ИМЕНА_ЭКРАНОВ[к]])) return ИМЕНА_ЭКРАНОВ[к];
    }
    return '';
  }

  function видим(экран) {
    return !!(экран && экран.classList.contains('экран--виден'));
  }

  function накнопку(имя, что) {
    var кнопка = document.getElementById(имя);
    if (!кнопка) {
      console.warn('Шашки: не нашёл кнопку «' + имя + '» — экраны выбора могут не переключаться');
      return;
    }
    кнопка.addEventListener('click', что);
  }

  /* ---------- Кто куда ведёт ---------- */

  накнопку('кнопка-режим-бот', function () { показатьПоИмени('экран-бота-шашек'); });
  накнопку('кнопка-бота-назад', показать);
  накнопку('кнопка-в-меню-шашки', уйтиВМеню);

  /* Две кнопки, которые начинают партию. Партию заводит js/шашки-экран.js,
     мы только открываем доску, чтобы её было видно. */
  накнопку('кнопка-с-ботом', показатьДоску);
  накнопку('кнопка-вдвоём', показатьДоску);

  /* Экраны игры по сети («Играть с другом», код стола, вход по коду)
     переключает не этот файл, а js/сеть.js через мост js/шашки-сеть.js:
     он один знает, есть ли недоигранная партия и куда человека вести.
     Поэтому кнопок «кнопка-с-другом», «кнопка-друг-назад» и прочих
     здесь нет — только подстраховка ниже, на случай, если файл связи
     не доехал. */

  /**
   * «В меню» из-под доски. Если шла партия по сети, это настоящий уход
   * из партии: друга надо предупредить, иначе он до конца просидит
   * в ожидании хода от того, кто уже ушёл.
   */
  function уйтиВМеню() {
    if (window.ШашкиСеть && window.ШашкиСеть.идёт()) window.ШашкиСеть.покинуть();
    показать();
  }

  /* Подстраховка: файл связи не доехал или упал на полпути.

     Кнопку «Играть с другом» обслуживает только он, и без него она молчала
     бы. Молчащая кнопка хуже сломанной — человек жмёт её снова и снова
     и решает, что зависла вся игра. Признак «файл на месте» — дверь
     «отправитьХод»: маленький js/похвастаться.js тоже создаёт window.Сеть,
     поэтому проверять само окно бесполезно. */
  var связьРаботает = !!(window.Сеть && typeof window.Сеть.отправитьХод === 'function');
  if (!связьРаботает) {
    console.warn('Игра с другом по сети не подключилась: файл js/сеть.js не загрузился ' +
                 'или упал с ошибкой. Игра с ботом и вдвоём работает как обычно.');
    накнопку('кнопка-с-другом', function () {
      показатьПоИмени('экран-друга');
      сказать('Игра по сети не загрузилась — обновите страницу (Ctrl+F5). ' +
              'С ботом и вдвоём на этом устройстве играть можно.');
    });
    накнопку('кнопка-друг-назад', показать);
  }

  /** Написать человеку на экране «Игра с другом». */
  function сказать(слова) {
    var строка = document.getElementById('сообщение-друга');
    if (!строка) return;
    строка.textContent = слова;
    строка.classList.remove('скрыт');
  }

  /* Переходник для общего файла связи. Когда сервер не отвечает, он
     предлагает человеку сыграть с ботом и жмёт кнопку с дураковым именем
     «кнопка-играть». У нас партию с ботом начинает «кнопка-с-ботом»,
     поэтому на странице стоит невидимая кнопка-переходник с дураковым
     именем, а нажатие переводится здесь. Чужой файл ради этого править
     не пришлось. */
  накнопку('кнопка-играть', function () {
    var старт = document.getElementById('кнопка-с-ботом');
    if (старт) старт.click();
  });

  window.ШашкиРежимы = {
    показать: показать,
    показатьДоску: показатьДоску,
    показатьПоИмени: показатьПоИмени,
    какойОткрыт: какойОткрыт,
    открыты: открыты
  };
})();
