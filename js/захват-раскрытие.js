// «Захват»: расписание раскрытия раунда (ТЗ 8.5, журнал — ТЗ 8.5 и 14).
// Берёт события разбора раунда (Правила.разобратьРаунд) и отдаёт чистые данные: что показать и в какую
// миллисекунду от начала раскрытия. Без DOM, без таймеров, без рисования, без случая и без часов:
// часы ведёт экран, он же рисует по шагам. Поэтому расписание одно и то же у всех игроков.
// Браузер берёт window.ЗахватРаскрытие, сервер и проверки — require (как у файла правил).
(function () {
  'use strict';

  const Карты = (typeof window !== 'undefined' && window.ЗахватКарты)
    ? window.ЗахватКарты
    : require('./захват-карты.js');

  // Правила нужны только для шанса в причине боя (ТЗ 8.5б п. 3): тот же шанс, что был на стрелке.
  // Берём при вызове, а не при загрузке: в песочнице проверок файла правил может не быть — тогда строк с шансом нет.
  function правила() {
    if (typeof window !== 'undefined' && window.ЗахватПравила) return window.ЗахватПравила;
    if (typeof require === 'function') {
      try { return require('./захват-правила.js'); } catch (ошибка) { return null; }
    }
    return null;
  }

  // ===================================================================
  // Время (ТЗ 8.5). Четыре части в сумме дают ровно 8000 мс.
  // ===================================================================
  const ФАЗЫ = [
    { имя: 'пластина', с: 0, длит: 1000 },
    { имя: 'стрелки', с: 1000, длит: 1000 },
    { имя: 'бои', с: 2000, длит: 4000 },
    { имя: 'итог', с: 6000, длит: 2000 }
  ];
  // Общее время — сумма частей, чтобы число 8000 было записано один раз (в частях выше).
  const ВСЕГО_МС = ФАЗЫ.reduce(function (сумма, ф) { return сумма + ф.длит; }, 0);
  const БОЙ_МС = 600; // одна цель
  // С ботами раскрытие «плотное» (ТЗ 8.5): итог держится секунду, бои занимают столько волн по БОЙ_МС, сколько их есть.
  const ИТОГ_ПЛОТНО_МС = 1000;
  const БОЁВ_ПОДРЯД_НЕ_БОЛЬШЕ = 6; // больше — идут пачками
  const ПАЧКА_БОЁВ = 4;
  // Внутри одного боя (от его начала): капли бегут по стрелке, цель вспыхивает и вздрагивает,
  // всплывают «−N», у взятой столицы трескается значок, потом область наливается новым цветом.
  const ВНУТРИ_БОЯ = {
    капли: { с: 0, длит: 300 },
    вспышка: { с: 300, длит: 100 },
    минус: { с: 300, длит: 300 },
    трещина: { с: 400, длит: 100 },
    перекраска: { с: 450, длит: 150 }
  };
  // Налив областей: соты проступают по одной (ТЗ 8.5): 0,3 с на соту, шаг 40 мс. Число сот знает экран.
  const НАЛИВ = { наСотуМс: 300, шагСотыМс: 40 };

  const МИНУС = '−';

  // Строка-ведущий под «Раунд 7 — раскрытие» по долям (ТЗ 8.5б п. 2): объясняет, что значат метки.
  // «+N» и «−N» здесь — сами слова-образцы, а не числа. В доле итога ведущего нет: там итог раунда.
  const ВЕДУЩИЙ = {
    пластина: '+N — новые войска соперников',
    стрелки: 'Стрелки: число — сколько войск идёт',
    бои: 'Бой: ' + МИНУС + 'N — сколько погибло'
  };

  // ===================================================================
  // Слова: склонения по-простому. Имена игроков свободные, поэтому родительный падеж — по окончанию
  // (Петя → Пети, Маша → Маши, Иван → Ивана); у редких имён возможна неточность, у латиницы имя не меняется.
  // ===================================================================
  const ГЛАСНЫЕ = 'аеёиоуыэюя';

  function родительный(имя) {
    const строка = String(имя);
    if (!строка) return строка;
    // Боты зовутся «Бот N»: цифра на конце склонение сбивает, поэтому они — особый случай.
    if (/^Бот \d+$/.test(строка)) return 'Бота' + строка.slice(3);
    const настоящая = строка.slice(-1);
    const последняя = настоящая.toLowerCase();
    const основа = строка.slice(0, -1);
    if (!/[а-яё]/.test(последняя)) return строка;
    // Имя ПЕТЯ пишется заглавными — и окончание берём заглавным: ПЕТИ.
    const заглавная = настоящая !== последняя;
    const окончание = function (с) { return заглавная ? с.toUpperCase() : с; };
    if (последняя === 'я') return основа + окончание('и');
    if (последняя === 'а') {
      const перед = основа.slice(-1).toLowerCase();
      return основа + окончание('гкхжчшщ'.indexOf(перед) !== -1 ? 'и' : 'ы');
    }
    if (последняя === 'й' || последняя === 'ь') return основа + окончание('я');
    if (ГЛАСНЫЕ.indexOf(последняя) !== -1) return строка;
    return строка + окончание('а');
  }

  // Область в винительном падеже: «взял Мельницу», «взял Брод».
  function винительный(имяОбласти) {
    const последняя = имяОбласти.slice(-1);
    if (последняя === 'а') return имяОбласти.slice(0, -1) + 'у';
    if (последняя === 'я') return имяОбласти.slice(0, -1) + 'ю';
    return имяОбласти;
  }

  // Род области по окончанию названия: ж — Мельница, Площадь; с — Ущелье; м — Брод. У «Столицы …» род всегда женский.
  function родОбласти(имяОбласти, столица) {
    if (столица) return 'ж';
    const последняя = имяОбласти.slice(-1);
    if (последняя === 'а' || последняя === 'я' || последняя === 'ь') return 'ж';
    if (последняя === 'е' || последняя === 'о') return 'с';
    return 'м';
  }

  const ВАШ = { м: 'ваш', ж: 'ваша', с: 'ваше' };
  const БЫЛ = { м: 'был', ж: 'была', с: 'было' };
  const УСТОЯЛ = { м: 'устоял', ж: 'устояла', с: 'устояло' };

  // 1 войско, 2–4 войска, 5+ войск (и 11–14 — «войск»).
  function склонить(n, один, два, пять) {
    const последняя = n % 10;
    const две = n % 100;
    if (две >= 11 && две <= 14) return пять;
    if (последняя === 1) return один;
    if (последняя >= 2 && последняя <= 4) return два;
    return пять;
  }

  function войска(n) {
    return n + ' ' + склонить(n, 'войско', 'войска', 'войск');
  }

  // ===================================================================
  // Строка равенства для итога партии (Г3д, решение 1). Одна на оба режима: с ботами и по сети.
  // Вход: места — массив Правила.места(партия) (по месту, лучший первым; у каждого кто, как, очки, войск,
  // взятоОбластей); я — ключ игрока; имена — {ключ: имя}. Выход: строка или '' (нет равенства, я не живой
  // или не найден). Сперва сравниваем с местом выше, потом с местом ниже; оба обязаны быть живыми.
  // ===================================================================
  function поЧислу(n, один, два, пять) {
    return 'по ' + n + ' ' + склонить(n, один, два, пять);
  }

  function чем(верхний, нижний) {
    // Какая ступень развела соседей. Если порядок ей противоречит (победитель по столицам стоит выше
    // по особому праву), честного объяснения нет — строки не будет.
    if (верхний.войск !== нижний.войск) return верхний.войск > нижний.войск ? 'войска' : null;
    if (верхний.взятоОбластей !== нижний.взятоОбластей) return верхний.взятоОбластей > нижний.взятоОбластей ? 'взято' : null;
    return 'номер';
  }

  function строкаРавенства(места, я, имена) {
    if (!Array.isArray(места) || я === undefined || я === null) return '';
    const название = имена || {};
    const и = места.findIndex(function (м) { return м.кто === я; });
    if (и === -1 || места[и].как !== 'живой') return '';
    const равный = function (с) { return с && с.как === 'живой' && с.очки === места[и].очки; };
    const другой = равный(места[и - 1]) ? места[и - 1] : (равный(места[и + 1]) ? места[и + 1] : null);
    if (!другой) return '';
    const верхний = места.indexOf(другой) < и ? другой : места[и];
    const нижний = верхний === другой ? места[и] : другой;
    const ступень = чем(верхний, нижний);
    if (!ступень) return '';
    const кого = function (м) { return м.кто === я ? 'у вас' : 'у ' + родительный(название[м.кто] || String(м.кто)); };
    const начало = 'У вас и ' + кого(другой) + ' ';
    const очки = поЧислу(места[и].очки, 'очку', 'очка', 'очков');
    if (ступень === 'войска') {
      return начало + очки + ' — выше тот, у кого больше войск на карте: ' +
        кого(верхний) + ' — ' + верхний.войск + ', ' + кого(нижний) + ' — ' + нижний.войск + '.';
    }
    if (ступень === 'взято') {
      return начало + очки + ' и ' + поЧислу(места[и].войск, 'войску', 'войска', 'войск') +
        ' — выше тот, кто взял больше областей за партию: ' +
        кого(верхний) + ' — ' + верхний.взятоОбластей + ', ' + кого(нижний) + ' — ' + нижний.взятоОбластей + '.';
    }
    return начало + 'всё поровну — выше тот, кто раньше в списке игроков.';
  }

  // ===================================================================
  // Вход: { события, раунд, карта: 'материк'|'остров', имена: {ключ: имя}, я?: ключ,
  //         хозяеваДо?, хозяеваПосле?, плотно?, всегоРаундов?, войскаДо? }. Имена и карта нужны для строк; «я» — для первой строки итога;
  // хозяева до и после раунда (массивы партии) — чтобы узнать «край взят»; плотно: true — раскрытие по числу
  // боёв (с ботами), без него — прежние 8000 мс; всегоРаундов — для подвала «Итог раунда 7 из 10» (нет — без «из N»).
  // войскаДо — войска по областям на начало раунда, до расстановки (тот же порядок, что партия.войска). Есть оно
  // вместе с хозяеваДо — шаги несут живой счёт (ТЗ 8.5б п. 1) и причины боя пишутся полностью; нет — как раньше.
  // ===================================================================
  function собратьКонтекст(вход) {
    if (!вход || !Array.isArray(вход.события)) throw new Error('Раскрытию нужен список событий разбора раунда');
    const карта = Карты.КАРТЫ[вход.карта];
    if (!карта) throw new Error('Раскрытию нужна карта: «материк» или «остров»');
    if (typeof вход.раунд !== 'number' || !isFinite(вход.раунд)) {
      throw new Error('Раскрытию нужен номер раунда (число), пришло: ' + String(вход.раунд));
    }
    const имена = вход.имена || {};
    return {
      вход: вход,
      карта: карта,
      имя: function (ключ) { return имена[ключ] || String(ключ); },
      область: function (номер) {
        const о = карта.области[номер - 1];
        return о ? о.имя : 'область ' + номер;
      }
    };
  }

  // Игрок в родительном падеже после «у»: сам человек — «вас», остальные — по имени («Бота 2»).
  function кого(к, ключ) {
    return ключ === к.вход.я ? 'вас' : родительный(к.имя(ключ));
  }

  // Игрок в именительном: сам человек — «Вы», остальные — по имени.
  function ктоИмя(к, ключ) {
    return ключ === к.вход.я ? 'Вы' : к.имя(ключ);
  }

  // «у Коли» / «у вас» / «без хозяина» — кто держал цель. Слова «ничья» игрок не видит (ТЗ, Слова).
  function укого(к, ключ) {
    return ключ === null || ключ === undefined ? 'без хозяина' : 'у ' + кого(к, ключ);
  }

  // Новый хозяин после захвата, по роду области: «ваш» / «ваша» / «у Бота 2».
  function новыйХозяин(к, ключ, род) {
    return ключ === к.вход.я ? ВАШ[род] : 'у ' + кого(к, ключ);
  }

  // Прежний хозяин в скобках журнала: «был у Бота 2» / «была ваша» / «был без хозяина».
  function прежнийХозяин(к, ключ, род) {
    if (ключ === null || ключ === undefined) return БЫЛ[род] + ' без хозяина';
    return БЫЛ[род] + ' ' + (ключ === к.вход.я ? ВАШ[род] : 'у ' + кого(к, ключ));
  }

  // «Столица Мельница» или просто «Мельница»: название области в строке захвата.
  function названиеЗахвата(к, с) {
    const куда = к.область(с.куда);
    return с.столица ? 'Столица ' + куда : куда;
  }

  // ===================================================================
  // Строки журнала (ТЗ 8.5 и 14). Возврат домой и расстановки строк не дают: это не события боя.
  // Выбывшего в журнал не пишем (в примере 14 его строки нет) — он назван в итоге раунда.
  // ===================================================================
  // Потери отбитого удара: нулевая часть не пишется (ТЗ 8.5), у обеих нулей — запасная фраза.
  function потериОтбитого(к, с, перед, еслиНет) {
    const части = [];
    if (с.выбитоНападающих > 0) части.push(ктоИмя(к, с.кто) + ' ' + МИНУС + с.выбитоНападающих);
    if (с.выбитоЗащитников > 0) {
      части.push((с.у === null || с.у === undefined ? 'защитники' : ктоИмя(к, с.у)) + ' ' + МИНУС + с.выбитоЗащитников);
    }
    return части.length ? перед + части.join(', ') : еслиНет;
  }

  // Игрок в творительном после «не за»: «за вами», «за Машей», «за Ботом 1». Имена свободные — по окончанию.
  function творительный(имя) {
    const строка = String(имя);
    if (/^Бот \d+$/.test(строка)) return 'Ботом' + строка.slice(3);
    const последняя = строка.slice(-1).toLowerCase();
    const основа = строка.slice(0, -1);
    if (!/[а-яё]/.test(последняя)) return строка;
    if (последняя === 'а') return основа + ('жчшщц'.indexOf(основа.slice(-1).toLowerCase()) !== -1 ? 'ей' : 'ой');
    if (последняя === 'я') return основа + 'ей';
    if (последняя === 'й' || последняя === 'ь') return основа + 'ем';
    if (ГЛАСНЫЕ.indexOf(последняя) !== -1) return строка;
    return строка + 'ом';
  }

  // Часть «Погибло: …»: у кого и сколько. Нулевая часть не пишется (ТЗ 8.5), у обеих нулей — «Погибших нет».
  // Без глаголов рода: «у Бота 1 — 2», «у вас — 2», «у защитников — 3» (ТЗ 8.5а).
  function потериУдара(к, с) {
    const части = [];
    if (с.выбитоНападающих > 0) части.push('у ' + кого(к, с.кто) + ' — ' + с.выбитоНападающих);
    if (с.выбитоЗащитников > 0) {
      const хозяин = с.у === null || с.у === undefined ? 'защитников' : кого(к, с.у);
      части.push('у ' + хозяин + ' — ' + с.выбитоЗащитников);
    }
    return части.length ? 'Погибло: ' + части.join(', ') : 'Погибших нет';
  }

  function строкаУдара(к, с) {
    const куда = к.область(с.куда);
    if (с.исход === 'взята') {
      // Рода игрока игра не знает, поэтому глагола при имени нет: род берёт только область (ТЗ 8.5а).
      const род = родОбласти(куда, с.столица);
      return названиеЗахвата(к, с) + ' теперь ' + новыйХозяин(к, с.кто, род) +
        ' (' + прежнийХозяин(к, с.у, род) + '): бой ' + с.сколько + ' против ' + с.защитников +
        ', там теперь ' + войска(с.осталось);
    }
    const чей = с.кто === к.вход.я ? 'Ваш удар' : 'Удар ' + родительный(к.имя(с.кто));
    const голова = чей + ' → ' + куда + ' (' + укого(к, с.у) + '): ' + с.сколько + ' против ' + с.защитников + ' — ';
    if (с.исход === 'отбит') {
      return голова + 'взять не удалось. ' + потериУдара(к, с);
    }
    return голова + 'все нападавшие погибли, ' +
      (с.у === null || с.у === undefined ? 'хозяина нет' : 'хозяин прежний');
  }

  function строкаВстречного(к, с) {
    const а = с.колонны[0];
    const б = с.колонны[1];
    // Названия областей — только в именительном (в данных нет творительного): «в пути (Брод и Мельница)».
    let строка = 'Колонны встретились в пути (' + к.область(с.области[0]) + ' и ' + к.область(с.области[1]) + '): у ' +
      кого(к, а.кто) + ' из ' + а.было + ' осталось ' + а.осталось + ', у ' + кого(к, б.кто) + ' из ' + б.было + ' — ' + б.осталось;
    if (с.исход === 'разошлись') строка += ' — уцелевшие пошли дальше';
    if (с.исход === 'обе погибли') строка += ' — погибли все';
    return строка;
  }

  function строкаРассеялись(к, с) {
    const одно = с.сколько % 10 === 1 && с.сколько % 100 !== 11;
    const дом = к.область(с.куда);
    const моё = с.кто === к.вход.я;
    // Дом без хозяина — «Холм без хозяина» (название области не склоняем: падежей областей в данных нет); иначе «Холм уже не ваш» / «уже не за Ботом 1».
    let почему;
    if (с.у === null || с.у === undefined) почему = дом + ' без хозяина';
    else if (моё) почему = дом + ' уже не ' + ВАШ[родОбласти(дом, false)];
    else почему = дом + ' уже не за ' + творительный(к.имя(с.кто));
    // «3 войска вас не нашли» по-русски не говорят: про человека — «Ваши 3 войска».
    const чьи = моё ? (одно ? 'Ваше ' : 'Ваши ') + войска(с.сколько) : войска(с.сколько) + ' ' + родительный(к.имя(с.кто));
    return чьи + (одно ? ' вернулось, а ' : ' вернулись, а ') + почему + ' — ' + (одно ? 'это войско пропало' : 'эти войска пропали');
  }

  // Строка журнала для события или null, если событие строки не даёт.
  function строкаЖурнала(к, с) {
    switch (с.вид) {
      case 'встречный': return строкаВстречного(к, с);
      case 'удар': return строкаУдара(к, с);
      case 'рассеялись': return строкаРассеялись(к, с);
      case 'перевод':
        return (с.кто === к.вход.я ? 'Ваш перевод' : 'Перевод ' + родительный(к.имя(с.кто))) + ': ' + к.область(с.откуда) + ' → ' + к.область(с.куда) +
          ', ' + войска(с.сколько);
      case 'сдался':
        // Без родовых слов («сдался/сдалась»): пол по имени не угадать.
        return 'Сдача: ' + к.имя(с.кто) + ' — области остались без хозяина';
      case 'черновик не принят':
        return (с.кто === к.вход.я ? 'Ваши приказы' : 'Приказы ' + родительный(к.имя(с.кто))) + ' не приняты: ' + с.причина;
      default: return null;
    }
  }

  // ===================================================================
  // Живой счёт (ТЗ 8.5б п. 1): метка всплыла — число под ней в тот же миг изменилось на столько же.
  // Шаг, который меняет число области, её хозяина или пилюлю стрелки, несёт поле
  //   счёт: { войска: [...], хозяева: [...], пилюли: { 'откуда-куда-кто': N } }
  // — полный снимок ПОСЛЕ шага (снимок, а не разница: пропуск шагов и пачки боёв не копят ошибок).
  // Изменение — маленькая запись: { область, плюс | стало, хозяин? } или { пилюля, плюс | стало | убрать }.
  // ===================================================================
  function ключПилюли(откуда, куда, кто) {
    return откуда + '-' + куда + '-' + кто;
  }

  // Что меняет запись: область или пилюля. По нему шаги одной области не обгоняют друг друга.
  function чтоМеняет(изменение) {
    return изменение.пилюля !== undefined ? 'п' + изменение.пилюля : 'о' + изменение.область;
  }

  // Счёт на начало раскрытия: чужие шайбы — войска на начало раунда; свои — как игрок их видел перед
  // «Готово» (начало + поставлено − отправлено), но по событиям раунда, а не по черновику; области
  // сдавшихся (шаг 0) — сразу без хозяина с теми же войсками. Без войскаДо или хозяеваДо счёта нет.
  function началоСчёта(к) {
    const вход = к.вход;
    if (!Array.isArray(вход.войскаДо) || !Array.isArray(вход.хозяеваДо)) return null;
    const войска = вход.войскаДо.slice();
    const хозяева = вход.хозяеваДо.slice();
    const я = вход.я;
    const естьЯ = я !== undefined && я !== null;
    вход.события.forEach(function (с) {
      if (с.вид === 'сдался') {
        хозяева.forEach(function (х, н) { if (н > 0 && х === с.кто) хозяева[н] = null; });
      }
      if (!естьЯ || с.кто !== я) return;
      if (с.вид === 'расстановка') войска[с.куда] += с.сколько;
      if (с.вид === 'приказ') войска[с.откуда] -= с.сколько;
    });
    return { войска: войска, хозяева: хозяева, пилюли: {} };
  }

  function снимокСчёта(состояние) {
    return {
      войска: состояние.войска.slice(),
      хозяева: состояние.хозяева.slice(),
      пилюли: Object.assign({}, состояние.пилюли)
    };
  }

  function применитьИзменение(состояние, и) {
    if (и.пилюля !== undefined) {
      if (и.убрать) { delete состояние.пилюли[и.пилюля]; return; }
      const стало = и.плюс !== undefined ? (состояние.пилюли[и.пилюля] || 0) + и.плюс : и.стало;
      // Пилюля с нулём — погибшая колонна: она гаснет.
      if (стало > 0) состояние.пилюли[и.пилюля] = стало;
      else delete состояние.пилюли[и.пилюля];
      return;
    }
    if (и.плюс !== undefined) состояние.войска[и.область] += и.плюс;
    else состояние.войска[и.область] = и.стало;
    if (Object.prototype.hasOwnProperty.call(и, 'хозяин')) состояние.хозяева[и.область] = и.хозяин;
  }

  // Счёт одного раскрытия: начало, изменения по шагам и время последнего изменения каждой области и пилюли.
  function новыйСчёт(к) {
    const начало = началоСчёта(к);
    if (!начало) return null;
    return { начало: начало, изменения: new Map(), когда: {} };
  }

  // Отметить шаг как меняющий счёт. Шаг встаёт не раньше прошлого изменения тех же областей и пилюль:
  // в пачке боёв второй удар по той же цели (или удар колонной после встречного) иначе показал бы «−N»
  // раньше, чем первый бой её перекрасил, — число прыгнуло бы мимо метки. Без счёта шаги не трогаются.
  function отметить(счёт, шаг, изменения) {
    if (!счёт) return шаг;
    let когда = шаг.с;
    изменения.forEach(function (и) {
      const раньше = счёт.когда[чтоМеняет(и)];
      if (раньше > когда) когда = раньше;
    });
    шаг.с = когда;
    изменения.forEach(function (и) { счёт.когда[чтоМеняет(и)] = когда; });
    счёт.изменения.set(шаг, изменения);
    return шаг;
  }

  // Снимки раздаются уже по шагам, разложенным по времени: в этом порядке их и увидит игрок.
  function разложитьСчёт(счёт, шаги) {
    if (!счёт) return;
    const состояние = снимокСчёта(счёт.начало);
    шаги.forEach(function (шаг) {
      const изменения = счёт.изменения.get(шаг);
      if (!изменения) return;
      изменения.forEach(function (и) { применитьИзменение(состояние, и); });
      шаг.счёт = снимокСчёта(состояние);
    });
  }

  // Колонны, которые пойдут домой на шаге 7, — в том же порядке, в каком их копит разбор: сперва
  // разошедшиеся во встречных, потом отбитые удары с выжившими. По нему «возврат» и «рассеялись»
  // находят свою пилюлю.
  function пилюлиДомой(события) {
    const очередь = [];
    события.forEach(function (с) {
      if (с.вид === 'встречный' && с.исход === 'разошлись') {
        с.колонны.forEach(function (кол) { очередь.push(ключПилюли(кол.откуда, кол.куда, кол.кто)); });
      } else if (с.вид === 'удар' && с.исход === 'отбит' && с.домой > 0) {
        очередь.push(ключПилюли(с.откуда[0].область, с.куда, с.кто));
      }
    });
    return очередь;
  }

  // ===================================================================
  // Шаги раскрытия
  // ===================================================================
  function шагПоПорядку(шаги, шаг) {
    шаги.push(шаг);
    return шаг;
  }

  // Начало боя по его порядковому номеру: до 6 боёв — по одному, больше — пачками (минимум по 4 разом),
  // чтобы все уложились в 4 секунды раздела боёв.
  function размерПачки(боёв) {
    if (боёв <= БОЁВ_ПОДРЯД_НЕ_БОЛЬШЕ) return 1;
    return Math.max(ПАЧКА_БОЁВ, Math.ceil(боёв / БОЁВ_ПОДРЯД_НЕ_БОЛЬШЕ));
  }

  // Части раскрытия. Онлайн — всегда прежние 8000 мс (сервер считает сроки раунда от них). С ботами («плотно»):
  // бои занимают волн × БОЙ_МС (без боёв — 0), итог — секунду; пластина и стрелки те же.
  function расписаниеФаз(плотно, боёв, пачка) {
    if (!плотно) return ФАЗЫ.map(function (ф) { return { имя: ф.имя, с: ф.с, длит: ф.длит }; });
    const волн = боёв === 0 ? 0 : Math.ceil(боёв / пачка);
    const бои = волн * БОЙ_МС;
    const началоИтога = ФАЗЫ[2].с + бои;
    return [
      { имя: ФАЗЫ[0].имя, с: ФАЗЫ[0].с, длит: ФАЗЫ[0].длит },
      { имя: ФАЗЫ[1].имя, с: ФАЗЫ[1].с, длит: ФАЗЫ[1].длит },
      { имя: ФАЗЫ[2].имя, с: ФАЗЫ[2].с, длит: бои },
      { имя: ФАЗЫ[3].имя, с: началоИтога, длит: ИТОГ_ПЛОТНО_МС }
    ];
  }

  function началоБоя(номерБоя, пачка) {
    return ФАЗЫ[2].с + Math.floor(номерБоя / пачка) * БОЙ_МС;
  }

  function шагиБояВстречного(к, с, начало, шаги, счёт) {
    шагПоПорядку(шаги, {
      вид: 'капли', с: начало + ВНУТРИ_БОЯ.капли.с, длит: ВНУТРИ_БОЯ.капли.длит,
      стрелки: с.колонны.map(function (кол) { return { кто: кол.кто, откуда: кол.откуда, куда: кол.куда }; })
    });
    шагПоПорядку(шаги, { вид: 'звук', имя: 'удар', с: начало + ВНУТРИ_БОЯ.вспышка.с, длит: 0 });
    шагПоПорядку(шаги, {
      вид: 'вспышка', с: начало + ВНУТРИ_БОЯ.вспышка.с, длит: ВНУТРИ_БОЯ.вспышка.длит, области: с.области.slice()
    });
    с.колонны.forEach(function (кол) {
      const потеряно = кол.было - кол.осталось;
      if (потеряно <= 0) return;
      // Пилюля колонны считает вниз; погибшая колонна (осталось 0) гаснет.
      отметить(счёт, шагПоПорядку(шаги, {
        вид: 'минус', с: начало + ВНУТРИ_БОЯ.минус.с, длит: ВНУТРИ_БОЯ.минус.длит,
        область: кол.откуда, кто: кол.кто, сколько: потеряно, текст: МИНУС + потеряно
      }), [{ пилюля: ключПилюли(кол.откуда, кол.куда, кол.кто), стало: кол.осталось }]);
    });
  }

  function шагиБояУдара(с, начало, шаги, счёт) {
    const капли = шагПоПорядку(шаги, {
      вид: 'капли', с: начало + ВНУТРИ_БОЯ.капли.с, длит: ВНУТРИ_БОЯ.капли.длит,
      стрелки: с.откуда.map(function (и) { return { кто: с.кто, откуда: и.область, куда: с.куда }; })
    });
    // Несколько стрелок одного игрока в одну цель в начале боя сливаются в пилюлю первой — с их суммой.
    const пилюля = ключПилюли(с.откуда[0].область, с.куда, с.кто);
    if (с.откуда.length > 1) {
      отметить(счёт, капли, [{ пилюля: пилюля, стало: с.сколько }].concat(с.откуда.slice(1).map(function (и) {
        return { пилюля: ключПилюли(и.область, с.куда, с.кто), убрать: true };
      })));
    }
    шагПоПорядку(шаги, { вид: 'звук', имя: 'удар', с: начало + ВНУТРИ_БОЯ.вспышка.с, длит: 0 });
    шагПоПорядку(шаги, {
      вид: 'вспышка', с: начало + ВНУТРИ_БОЯ.вспышка.с, длит: ВНУТРИ_БОЯ.вспышка.длит, области: [с.куда]
    });
    // «−N» у обеих сторон: у нападающих — над областью, откуда ушла первая колонна; у защитников — над целью.
    if (с.выбитоНападающих > 0) {
      отметить(счёт, шагПоПорядку(шаги, {
        вид: 'минус', с: начало + ВНУТРИ_БОЯ.минус.с, длит: ВНУТРИ_БОЯ.минус.длит,
        область: с.откуда[0].область, кто: с.кто, сколько: с.выбитоНападающих, текст: МИНУС + с.выбитоНападающих
      }), [{ пилюля: пилюля, стало: с.сколько - с.выбитоНападающих }]);
    }
    if (с.выбитоЗащитников > 0) {
      // Взята — в цели пока ноль, число выживших нападающих встанет с наливом. «Все погибли» — в области
      // остаётся минимум войск (с.осталось), это и показываем сразу; отбит — с.осталось и есть «было − d».
      отметить(счёт, шагПоПорядку(шаги, {
        вид: 'минус', с: начало + ВНУТРИ_БОЯ.минус.с, длит: ВНУТРИ_БОЯ.минус.длит,
        область: с.куда, кто: с.у, сколько: с.выбитоЗащитников, текст: МИНУС + с.выбитоЗащитников
      }), [{ область: с.куда, стало: с.исход === 'взята' ? с.защитников - с.выбитоЗащитников : с.осталось }]);
    }
    if (с.исход === 'взята' && с.столица) {
      шагПоПорядку(шаги, { вид: 'звук', имя: 'столица', с: начало + ВНУТРИ_БОЯ.трещина.с, длит: 0 });
      шагПоПорядку(шаги, {
        вид: 'трещина', с: начало + ВНУТРИ_БОЯ.трещина.с, длит: ВНУТРИ_БОЯ.трещина.длит, область: с.куда
      });
    }
    if (с.исход === 'взята') {
      шагПоПорядку(шаги, { вид: 'звук', имя: 'захват', с: начало + ВНУТРИ_БОЯ.перекраска.с, длит: 0 });
      // Хозяин и число меняются в начале налива; колонна вошла в область — её пилюля гаснет.
      отметить(счёт, шагПоПорядку(шаги, {
        вид: 'перекраска', с: начало + ВНУТРИ_БОЯ.перекраска.с, длит: ВНУТРИ_БОЯ.перекраска.длит,
        область: с.куда, на: с.кто, у: с.у === undefined ? null : с.у,
        наСотуМс: НАЛИВ.наСотуМс, шагСотыМс: НАЛИВ.шагСотыМс
      }), [{ область: с.куда, стало: с.осталось, хозяин: с.кто }, { пилюля: пилюля, убрать: true }]);
    }
  }

  // ===================================================================
  // Причина боя (ТЗ 8.5б п. 3): почему ваш бой кончился так. Только для ваших боёв: ваш удар, удар по
  // вам, встречный с вами. Обозначения ТЗ: N — сколько вы послали в цель, Н — сколько дошло
  // (удар.сколько), Ж — защитников на начало раунда (войскаДо[цель], это число вы видели на карте),
  // Д — защитников в бою (удар.защитников). Шанс — Правила.шанс(N, Ж), ровно тот, что был на стрелке.
  // Первая подошедшая строка таблицы; нет подходящей — null. Без войскаДо строк с Ж и шансом нет.
  // ===================================================================
  function этоЯ(к, ключ) {
    const я = к.вход.я;
    return я !== undefined && я !== null && ключ === я;
  }

  // Сумма приказов игрока: в цель (только удары) или из области (любые — «увели»).
  function посланоВ(события, кто, цель) {
    return события.reduce(function (сумма, с) {
      return с.вид === 'приказ' && с.приказ === 'удар' && с.кто === кто && с.куда === цель ? сумма + с.сколько : сумма;
    }, 0);
  }

  function уведеноИз(события, кто, область) {
    return события.reduce(function (сумма, с) {
      return с.вид === 'приказ' && с.кто === кто && с.откуда === область ? сумма + с.сколько : сумма;
    }, 0);
  }

  // Первый удар другого игрока в ту же цель раньше этого (в разборе удары по цели идут подряд).
  function первыйЧужойУдар(события, с) {
    for (let и = 0; и < события.length && события[и] !== с; и++) {
      const д = события[и];
      if (д.вид === 'удар' && д.куда === с.куда && д.кто !== с.кто) return д;
    }
    return null;
  }

  // Шанс, как его показывала стрелка: проценты текстом и числом (правила знают предел показа и «<1 %»).
  function шансСтрелки(П, N, Ж) {
    if (typeof П.процентШанса === 'function') return П.процентШанса(N, Ж);
    const процент = Math.round(П.шанс(N, Ж) * 100);
    return { процент: процент, текст: процент + ' %' };
  }

  function причинаВашегоУдара(к, с) {
    const события = к.вход.события;
    const N = посланоВ(события, с.кто, с.куда);
    if (N > с.сколько) return 'Перехват по пути: дошли ' + с.сколько + ' из ' + N;
    const первый = первыйЧужойУдар(события, с);
    if (первый) return 'Первый удар туда — у ' + родительный(к.имя(первый.кто));
    const до = к.вход.войскаДо;
    if (!Array.isArray(до) || typeof до[с.куда] !== 'number') return null;
    const Ж = до[с.куда];
    const Д = с.защитников;
    const взял = с.исход === 'взята';
    if (Д > Ж) return 'Защитников ' + Д + ', а не ' + Ж + ': подкрепили';
    if (взял && Д < Ж) return 'Защитников ' + Д + ', а не ' + Ж + ': ушли в бой';
    const П = правила();
    if (!П || typeof П.шанс !== 'function') return null;
    if (!взял && П.шанс(N, Ж) === 0) return 'Взять было нельзя: ' + N + ' против ' + Ж;
    const шанс = шансСтрелки(П, N, Ж);
    if (!взял) return 'Шанс был ' + шанс.текст + (шанс.процент >= 50 ? ' — не повезло' : ' — мало войск');
    if (шанс.процент < 50) return 'Шанс был ' + шанс.текст + ' — повезло';
    return null; // взял, как и ждали
  }

  function причинаБоя(к, с) {
    const я = к.вход.я;
    if (я === undefined || я === null || !с) return null;
    if (с.вид === 'встречный') {
      const моя = с.колонны.find(function (кол) { return кол.кто === я; });
      if (!моя) return null;
      // Не дошла — погибла или повернула домой, когда обмены кончились.
      if (моя.осталось === 0 || с.исход === 'разошлись') return 'Перехват: вам ударили навстречу';
      return 'Колонны встретились на границе';
    }
    if (с.вид !== 'удар') return null;
    if (этоЯ(к, с.кто)) return причинаВашегоУдара(к, с);
    if (!этоЯ(к, с.у) || с.исход !== 'взята') return null; // удар по вам отбит — вышло как ждали
    const увели = уведеноИз(к.вход.события, я, с.куда);
    if (увели > 0) {
      return 'Вы увели ' + увели + ' — дома ' + склонить(с.защитников, 'остался', 'осталось', 'осталось') + ' ' + с.защитников;
    }
    return 'Пришли ' + с.сколько + ' против ваших ' + с.защитников;
  }

  // ===================================================================
  // Итог раунда (ТЗ 8.5): первая строка про вас, потом две строки событий по порядку МЕСТО (ниже).
  // ===================================================================
  function участвовал(события, ключ) {
    // Участник — тот, кто ставил, бил, дрался встречным боем, был целью удара (у), сдался или выбыл.
    return события.some(function (с) {
      if (с.вид === 'встречный') return с.колонны.some(function (кол) { return кол.кто === ключ; });
      if (с.вид === 'удар' && с.у === ключ) return true;
      return с.кто === ключ && (с.вид === 'расстановка' || с.вид === 'приказ' || с.вид === 'удар' ||
        с.вид === 'сдался' || с.вид === 'выбыл');
    });
  }

  function строкаПроВас(к, события, ключ) {
    let взято = 0;
    let потеряноОбластей = 0;
    let потеряноВойск = 0;
    let былОтбитый = false;
    let отбитПоВам = false;
    let били = false; // был ли у вас свой удар или встречный бой в этом раунде
    события.forEach(function (с) {
      if (с.вид === 'встречный' && с.колонны.some(function (кол) { return кол.кто === ключ; })) били = true;
      if (с.вид === 'удар') {
        if (с.кто === ключ) били = true;
        if (с.кто === ключ && ударНеВзял(с)) былОтбитый = true;
        if (с.у === ключ && ударНеВзял(с)) отбитПоВам = true;
        if (с.исход === 'взята' && с.кто === ключ) взято++;
        if (с.исход === 'взята' && с.у === ключ) потеряноОбластей++;
        if (с.кто === ключ) потеряноВойск += с.выбитоНападающих;
        if (с.у === ключ) потеряноВойск += с.выбитоЗащитников;
      } else if (с.вид === 'встречный') {
        с.колонны.forEach(function (кол) { if (кол.кто === ключ) потеряноВойск += кол.было - кол.осталось; });
      } else if (с.вид === 'рассеялись' && с.кто === ключ) {
        потеряноВойск += с.сколько;
      }
    });
    // Коротко, чтобы влезло в 36 знаков на 320 (ТЗ 8.5): «Вы: +2 обл, −1 обл, погибло 12 войск». Номер раунда — в подвале.
    const части = [];
    if (взято > 0) части.push('+' + взято + ' обл');
    if (потеряноОбластей > 0) части.push(МИНУС + потеряноОбластей + ' обл');
    // Били, но не взяли — так и пишем: «без потерь» звучало бы так, будто ничего не было.
    // Ваш отбитый удар важнее удара по вам (ТЗ 8.5, Г3г).
    if (!части.length && былОтбитый) части.push('не взяли');
    else if (!части.length && отбитПоВам) {
      return 'Вы отбились' + (потеряноВойск > 0 ? ', погибло ' + войска(потеряноВойск) : ' без потерь');
    }
    if (потеряноВойск > 0) части.push('погибло ' + войска(потеряноВойск));
    if (!части.length && !били) return 'Вы не ударили, вас не тронули'; // «без потерь» тому, кто не ходил, ничего не говорит
    let строка = 'Вы: ' + (части.length ? части.join(', ') : 'без потерь');
    // Если строка слишком длинная, опустить потери областей
    if (строка.length > 36 && потеряноОбластей > 0) {
      // Найти и удалить элемент про потерянные области (начинается с МИНУС и содержит ' обл')
      const индекс = части.findIndex(function (ч) { return ч.indexOf(МИНУС) === 0 && ч.indexOf(' обл') > -1; });
      if (индекс > -1) части.splice(индекс, 1);
      строка = 'Вы: ' + (части.length ? части.join(', ') : 'без потерь');
    }
    return строка;
  }

  function строкаОбщая(события) {
    const взято = события.filter(function (с) { return с.вид === 'удар' && с.исход === 'взята'; }).length;
    return 'Взято областей: ' + взято;
  }

  // Края, которые в этом раунде достались одному игроку целиком.
  function взятыеКрая(к) {
    const до = к.вход.хозяеваДо;
    const после = к.вход.хозяеваПосле;
    if (!до || !после) return [];
    const найдено = [];
    к.карта.края.forEach(function (край) {
      const хозяин = после[край.области[0]];
      if (хозяин === null || хозяин === undefined) return;
      const весь = край.области.every(function (н) { return после[н] === хозяин; });
      const былоУЭтого = край.области.every(function (н) { return до[н] === хозяин; });
      if (весь && !былоУЭтого) найдено.push({ название: край.название, кто: хозяин, области: край.области, прибавка: край.прибавка });
    });
    return найдено;
  }

  // Края, которые целиком были у вас до раунда, а теперь не целиком у вас (Г3з, реш. 2). Если край целиком
  // взял другой игрок, он попадает в взятыеКрая («теперь у Бота 1»), а здесь его нет: две строки про одно — лишнее.
  function потерянныеКрая(к) {
    const я = к.вход.я;
    const до = к.вход.хозяеваДо;
    const после = к.вход.хозяеваПосле;
    if (я === undefined || я === null || !до || !после) return [];
    const найдено = [];
    к.карта.края.forEach(function (край) {
      if (!край.области.every(function (н) { return до[н] === я; })) return;
      if (край.области.every(function (н) { return после[н] === я; })) return;
      const хозяин = после[край.области[0]];
      const целикомДругой = хозяин !== null && хозяин !== undefined &&
        край.области.every(function (н) { return после[н] === хозяин; });
      if (целикомДругой) return;
      найдено.push({
        название: край.название, прибавка: край.прибавка, все: край.области.slice(),
        области: край.области.filter(function (н) { return после[н] !== я; })
      });
    });
    return найдено;
  }

  // «Край «Кряж» ваш: +2 войска в раунд» / «Край «Кряж» теперь у Бота 1» — взятый край.
  function строкаВзятогоКрая(к, край) {
    if (край.кто === к.вход.я) return 'Край «' + край.название + '» ваш: +' + войска(край.прибавка) + ' в раунд';
    return 'Край «' + край.название + '» теперь у ' + кого(к, край.кто);
  }

  // «Край «Кряж» потерян: −2 войска в раунд».
  function строкаПотерянногоКрая(край) {
    return 'Край «' + край.название + '» потерян: ' + МИНУС + войска(край.прибавка) + ' в раунд';
  }

  // Все строки про края раунда: сперва взятые, потом потерянные вами. Одни и те же — для пластины и журнала.
  // «области» — перешедшие в этом раунде; «все» — весь край: экран обводит его контуром (крайИтога).
  function строкиКраёв(к) {
    const списокСтрок = [];
    взятыеКрая(к).forEach(function (край) {
      const взятые = край.области.filter(function (н) { return к.вход.хозяеваДо[н] !== край.кто; });
      списокСтрок.push({
        место: крайСвой(к, край) ? МЕСТО.крайВаш : МЕСТО.крайЧужой,
        край: { название: край.название, области: взятые, все: край.области.slice() },
        текст: строкаВзятогоКрая(к, край)
      });
    });
    потерянныеКрая(к).forEach(function (край) {
      списокСтрок.push({
        место: МЕСТО.крайВаш, // потерянный край бывает только ваш
        край: { название: край.название, области: край.области, все: край.все },
        текст: строкаПотерянногоКрая(край)
      });
    });
    return списокСтрок;
  }

  // Удар, который не взял область: отбит или все нападавшие погибли — для игрока это одно и то же.
  function ударНеВзял(с) {
    return с.вид === 'удар' && с.исход !== 'взята';
  }

  // Места событий в выборе двух строк пластины (ТЗ 8.5, итог раунда, п. 2): чем меньше число, тем раньше.
  // а) взятая столица и выбывший — первыми, чьи бы ни были; б) с вашим участием; в) чужие.
  // Одинаковые по месту идут в порядке разбора (сортировка устойчивая); повторять одно место можно.
  const МЕСТО = {
    столица: 0, выбыл: 1,
    уВасВзяли: 10, выВзяли: 11, крайВаш: 12, встречныйСВами: 13, вашУдарОтбит: 14, поВамОтбит: 15,
    крайЧужой: 20, встречныйЧужой: 21, захватЧужой: 22, отбитЧужой: 23
  };

  function ктоВБою(с, ключ) {
    if (ключ === undefined || ключ === null) return false;
    if (с.вид === 'встречный') return с.колонны.some(function (кол) { return кол.кто === ключ; });
    return с.кто === ключ || с.у === ключ;
  }

  // Строка пластины про захват: «Форум теперь ваш: 4 против 3», «Ваша столица теперь у Коли».
  function строкаЗахватаДляПластины(к, с) {
    const я = к.вход.я;
    const куда = к.область(с.куда);
    if (с.столица) {
      const имя = с.у !== null && с.у !== undefined && с.у === я ? 'Ваша столица' : 'Столица ' + куда;
      return имя + ' теперь ' + новыйХозяин(к, с.кто, 'ж');
    }
    return куда + ' теперь ' + новыйХозяин(к, с.кто, родОбласти(куда, false)) + ': ' + с.сколько + ' против ' + с.защитников;
  }

  // Встречный бой: «Встречный бой: Вы −5, Маша −6» — сколько потеряла каждая колонна.
  function строкаВстречногоДляПластины(к, с) {
    const части = [];
    с.колонны.forEach(function (кол) {
      if (кол.было - кол.осталось > 0) части.push(ктоИмя(к, кол.кто) + ' ' + МИНУС + (кол.было - кол.осталось));
    });
    return части.length ? 'Встречный бой: ' + части.join(', ') : 'Встречный бой: без потерь';
  }

  function местоУдара(с, я) {
    if (с.исход === 'взята') {
      if (с.столица) return МЕСТО.столица;
      if (с.у === я) return МЕСТО.уВасВзяли;
      if (с.кто === я) return МЕСТО.выВзяли;
      return МЕСТО.захватЧужой;
    }
    if (с.кто === я) return МЕСТО.вашУдарОтбит;
    if (с.у === я) return МЕСТО.поВамОтбит;
    return МЕСТО.отбитЧужой;
  }

  // Край «ваш»: он теперь у вас или целиком был у вас до раунда (ваш край взят).
  function крайСвой(к, край) {
    const я = к.вход.я;
    if (я === undefined || я === null) return false;
    if (край.кто === я) return true;
    const до = к.вход.хозяеваДо;
    return !!до && край.области.every(function (н) { return до[н] === я; });
  }

  // Каждое главное событие: место (кто раньше), текст, области, названные в строке (для подписей на карте).
  function главныеСобытия(к, события) {
    const я = к.вход.я;
    const список = [];
    события.forEach(function (с) {
      const до = список.length;
      if (с.вид === 'выбыл') {
        список.push({ место: МЕСТО.выбыл, области: [], текст: 'Выбывает из игры: ' + к.имя(с.кто) });
      } else if (с.вид === 'удар' && с.исход === 'взята') {
        список.push({ место: местоУдара(с, я), области: [с.куда], текст: строкаЗахватаДляПластины(к, с) });
      } else if (с.вид === 'удар' && ударНеВзял(с)) {
        // Г3з, реш. 5: «Площадь устояла: Бот 1 −2, Бот 2 −1». Защитники области без хозяина — просто «защитники».
        const имя = к.область(с.куда);
        список.push({ место: местоУдара(с, я), области: [с.куда],
          текст: имя + ' ' + УСТОЯЛ[родОбласти(имя, false)] + потериОтбитого(к, с, ': ', ', без потерь') });
      } else if (с.вид === 'встречный') {
        список.push({ место: ктоВБою(с, я) ? МЕСТО.встречныйСВами : МЕСТО.встречныйЧужой,
          области: [с.области[0], с.области[1]], текст: строкаВстречногоДляПластины(к, с) });
      }
      // Строке боя — её событие и причина (ТЗ 8.5б п. 3): итог раунда ставит причину третьей строкой.
      if (список.length > до && (с.вид === 'удар' || с.вид === 'встречный')) {
        список[до].событие = с;
        список[до].причина = причинаБоя(к, с);
      }
    });
    строкиКраёв(к).forEach(function (строка) {
      список.push({ место: строка.место, области: [], край: строка.край, текст: строка.текст });
    });
    return список.sort(function (а, б) { return а.место - б.место; });
  }

  // Области, которые вы в этом раунде взяли, потеряли или куда ваш удар отбили (ТЗ 8.4.1): подписаны всегда.
  // Сначала потери, потом захваты, потом отбитые; внутри — в порядке разбора.
  function своиОбласти(к, события) {
    const я = к.вход.я;
    if (я === undefined || я === null) return [];
    const найденные = [];
    события.forEach(function (с) {
      if (с.вид !== 'удар' || (с.кто !== я && с.у !== я)) return;
      const порядок = с.исход === 'взята' ? (с.у === я ? 0 : 1) : 2;
      найденные.push({ область: с.куда, порядок: порядок });
    });
    return найденные.sort(function (а, б) { return а.порядок - б.порядок; }).map(function (н) { return н.область; });
  }

  // Подписи областей на карте на время пластины (ТЗ 8.4.1): не больше 4, по одной на область.
  // Первыми ваши взятые, потерянные и отбитые; потом названные в строках. Край подписью не ставится:
  // подпись «край …» не влезала в пилюлю, край показывается контуром (крайИтога).
  function собратьПодписи(к, события, выбранные) {
    const занято = {};
    const подписи = [];
    function назвать(н) {
      if (занято[н]) return;
      занято[н] = true;
      подписи.push({ область: н, текст: к.область(н) });
    }
    своиОбласти(к, события).forEach(назвать);
    выбранные.forEach(function (г) { г.области.forEach(назвать); });
    return подписи.slice(0, 4).map(function (п) { return { область: п.область, текст: п.текст }; });
  }

  // Номера всех областей края первой по порядку строки края среди выбранных, иначе null. Вторую строку
  // края называет только текст: контуры двух краёв слились бы в одну фигуру.
  function крайИтога(выбранные) {
    const строка = выбранные.find(function (г) { return !!г.край; });
    return строка ? строка.край.все.slice() : null;
  }

  // Стрелки ударов, взявших ваши области (Г3з, реш. 7): от каждой области-источника колонны к взятой области,
  // не больше трёх, первые по порядку разбора. Отбитые удары по вам стрелок не дают. Без «я» — пусто.
  const СТРЕЛОК_ИТОГА_НЕ_БОЛЬШЕ = 3;
  function стрелкиУдаровПоВам(к, события) {
    const я = к.вход.я;
    const список = [];
    if (я === undefined || я === null) return список;
    события.forEach(function (с) {
      if (с.вид !== 'удар' || с.исход !== 'взята' || с.у !== я) return;
      с.откуда.forEach(function (и) { список.push({ кто: с.кто, из: и.область, в: с.куда }); });
    });
    return список.slice(0, СТРЕЛОК_ИТОГА_НЕ_БОЛЬШЕ);
  }

  // Строки 2–3 итога. Есть ваш бой с причиной (ТЗ 8.5б п. 3) — самый важный такой бой: строка 2 его
  // событие, строка 3 его причина, второе событие уходит в журнал. Исключение «а» (взятая столица,
  // выбывший): та строка остаётся второй, ваш бой — третьей, причина — только в журнале. Причин нет —
  // две выбранные строки, как раньше. Подписи и контур края считаются от выбранных: их ТЗ не меняет.
  function строкиСобытий(главные, выбранные) {
    const сПричиной = главные.find(function (г) { return !!г.причина; });
    if (!сПричиной) return выбранные.map(function (г) { return г.текст; });
    const первая = главные[0];
    if (первая !== сПричиной && первая.место <= МЕСТО.выбыл) return [первая.текст, сПричиной.текст];
    return [сПричиной.текст, сПричиной.причина];
  }

  // Строки итога: про вас (или общая) и две строки событий — по месту из МЕСТО, оба могут быть одного рода.
  // Номер раунда сюда не входит: он в подвале («Раунд N · Журнал ›»). Вместе со строками отдаёт подписи и край.
  function итогРаунда(к, события) {
    const я = к.вход.я;
    const есть = я !== undefined && я !== null;
    const сдался = есть && события.some(function (с) { return с.вид === 'сдался' && с.кто === я; });
    const выбыл = есть && события.some(function (с) { return с.вид === 'выбыл' && с.кто === я; });
    // Выбывшему и наблюдателю — общая строка: про «вас» говорить уже нечего (ТЗ 8.5).
    const проВас = есть && !выбыл && участвовал(события, я);
    const строки = [сдался ? 'Вы сдались' : (проВас ? строкаПроВас(к, события, я) : строкаОбщая(события))];
    // «Боёв не было» — только когда не было ни удара, ни встречного боя (отбитый удар — тоже бой).
    const былБой = события.some(function (с) { return с.вид === 'удар' || с.вид === 'встречный'; });
    const главные = главныеСобытия(к, события);
    if (!былБой && !главные.length) {
      строки.push('Боёв в этом раунде не было');
      return { строки: строки, подписи: [], край: null, стрелки: [] };
    }
    const выбранные = главные.slice(0, 2);
    строкиСобытий(главные, выбранные).forEach(function (текст) { строки.push(текст); });
    return {
      строки: строки, подписи: собратьПодписи(к, события, выбранные), край: крайИтога(выбранные),
      стрелки: стрелкиУдаровПоВам(к, события)
    };
  }

  // ===================================================================
  // Главная функция
  // ===================================================================
  function построить(вход) {
    const к = собратьКонтекст(вход);
    const события = вход.события;
    const шаги = [];
    const журнал = [];
    const боёв = события.filter(function (с) { return с.вид === 'встречный' || с.вид === 'удар'; }).length;
    const пачка = размерПачки(боёв);
    const фазы = расписаниеФаз(вход.плотно === true, боёв, пачка);
    const всегоМс = фазы.reduce(function (сумма, ф) { return сумма + ф.длит; }, 0);

    // Живой счёт — только когда пришли войска на начало раунда (ТЗ 8.5б); иначе шаги как раньше.
    const счёт = новыйСчёт(к);
    const свой = function (ключ) { return !!счёт && вход.я !== undefined && вход.я !== null && ключ === вход.я; };

    // 0–1 с: пластина, «+N» всех расстановок разом, звук «раскрытие».
    // Под строкой раунда — строка-ведущий доли (ТЗ 8.5б п. 2); пропуск подписан кнопкой «Пропустить ›» в панели.
    шагПоПорядку(шаги, { вид: 'звук', имя: 'раскрытие', с: 0, длит: 0 });
    const пластина = шагПоПорядку(шаги, {
      вид: 'пластина', с: 0, длит: фазы[0].длит, текст: 'Раунд ' + вход.раунд + ' — раскрытие',
      строки: ['Раунд ' + вход.раунд + ' — раскрытие', ВЕДУЩИЙ.пластина]
    });
    // Первый снимок — счёт на начало раскрытия (без изменений).
    отметить(счёт, пластина, []);
    события.forEach(function (с) {
      if (с.вид !== 'расстановка') return;
      // Свои «+N» не повторяются: при живом счёте они уже в числе с мига касания.
      if (свой(с.кто)) return;
      отметить(счёт, шагПоПорядку(шаги, {
        вид: 'плюс', с: 0, длит: ФАЗЫ[0].длит, область: с.куда, кто: с.кто, сколько: с.сколько, текст: '+' + с.сколько
      }), [{ область: с.куда, плюс: с.сколько }]);
    });

    // 1–2 с: все стрелки разом, цветом хозяев (и приказы, и переводы).
    шагПоПорядку(шаги, {
      вид: 'пластина', с: фазы[1].с, длит: фазы[1].длит, текст: пластина.текст,
      строки: [пластина.текст, ВЕДУЩИЙ.стрелки]
    });
    события.forEach(function (с) {
      if (с.вид !== 'приказ') return;
      // Шайба-источник чужой колонны уменьшается в миг стрелки; свои уже вычтены в начале.
      const изменения = [{ пилюля: ключПилюли(с.откуда, с.куда, с.кто), плюс: с.сколько }];
      if (!свой(с.кто)) изменения.push({ область: с.откуда, плюс: -с.сколько });
      отметить(счёт, шагПоПорядку(шаги, {
        вид: 'стрелка', с: ФАЗЫ[1].с, длит: ФАЗЫ[1].длит,
        кто: с.кто, откуда: с.откуда, куда: с.куда, сколько: с.сколько, приказ: с.приказ
      }), изменения);
    });
    if (боёв > 0) {
      шагПоПорядку(шаги, {
        вид: 'пластина', с: фазы[2].с, длит: фазы[2].длит, текст: пластина.текст,
        строки: [пластина.текст, ВЕДУЩИЙ.бои]
      });
    }
    const домой = счёт ? пилюлиДомой(события) : [];

    // Бои (с 2 с). Встречные идут первыми — так их и выдаёт разбор, — потом удары по целям.
    let номерБоя = 0;
    // Время строки без боя (перевод) — время последнего начавшегося боя: порядок шагов «журнал»
    // тогда совпадает с порядком строк в массиве журнала.
    let последнийБой = ФАЗЫ[2].с;
    события.forEach(function (с) {
      let когдаСтрока = последнийБой;
      if (с.вид === 'встречный' || с.вид === 'удар') {
        const начало = началоБоя(номерБоя, пачка);
        номерБоя++;
        if (с.вид === 'встречный') шагиБояВстречного(к, с, начало, шаги, счёт);
        else шагиБояУдара(с, начало, шаги, счёт);
        когдаСтрока = начало;
        последнийБой = начало;
      } else if (с.вид === 'сдался' || с.вид === 'черновик не принят') {
        когдаСтрока = 0;
      } else if (с.вид === 'рассеялись') {
        когдаСтрока = фазы[3].с;
      }
      шагиСчётаБезБоя(с, когдаСтрока);
      const строка = строкаЖурнала(к, с);
      if (строка === null) return;
      // У ваших боёв в конце — причина через точку (ТЗ 8.5б п. 3); у чужих причины нет.
      const причина = причинаБоя(к, с);
      const текст = причина ? строка + '. ' + причина : строка;
      журнал.push(текст);
      const шагЖурнала = шагПоПорядку(шаги, { вид: 'журнал', с: когдаСтрока, длит: 0, текст: текст });
      // Рассеявшаяся колонна гаснет без метки — строкой журнала.
      if (счёт && с.вид === 'рассеялись') отметить(счёт, шагЖурнала, [{ пилюля: домой.shift(), убрать: true }]);
    });

    // Перевод и возврат меняют число только при живом счёте: «+N» у цели, стрелка гаснет (ТЗ 8.5б п. 1).
    function шагиСчётаБезБоя(с, когда) {
      if (!счёт) return;
      if (с.вид === 'перевод') {
        отметить(счёт, шагПоПорядку(шаги, {
          вид: 'плюс', с: когда, длит: БОЙ_МС, область: с.куда, кто: с.кто, сколько: с.сколько, текст: '+' + с.сколько
        }), [{ область: с.куда, плюс: с.сколько }, { пилюля: ключПилюли(с.откуда, с.куда, с.кто), убрать: true }]);
      } else if (с.вид === 'возврат') {
        отметить(счёт, шагПоПорядку(шаги, {
          вид: 'плюс', с: фазы[3].с, длит: БОЙ_МС, область: с.куда, кто: с.кто, сколько: с.сколько, текст: '+' + с.сколько
        }), [{ область: с.куда, плюс: с.сколько }, { пилюля: домой.shift(), убрать: true }]);
      }
    }

    // Строки краёв — в самом конце журнала раунда, вместе с итогом (Г3з, реш. 2).
    строкиКраёв(к).forEach(function (строка) {
      журнал.push(строка.текст);
      шагПоПорядку(шаги, { вид: 'журнал', с: фазы[3].с, длит: 0, текст: строка.текст });
    });

    // Последняя часть: карта в итоговом виде, пластина сменяется итогом раунда.
    const сведения = итогРаунда(к, события);
    const итог = сведения.строки;
    const подписиИтога = сведения.подписи;
    const краяИтога = сведения.край;
    const стрелкиИтога = сведения.стрелки;
    const изСкольких = typeof вход.всегоРаундов === 'number' && isFinite(вход.всегоРаундов) && вход.всегоРаундов > 0
      ? ' из ' + вход.всегоРаундов : '';
    const подвалИтога = 'Итог раунда ' + вход.раунд + изСкольких + ' · Подробно ›';
    шагПоПорядку(шаги, { вид: 'итоговая-карта', с: фазы[3].с, длит: фазы[3].длит });
    // «подписи» — договор со столом и экраном: области, подписанные на карте до ухода пластины;
    // «подвал» — нижняя мелкая строка пластины (номер раунда и вход в журнал).
    шагПоПорядку(шаги, {
      вид: 'итог-раунда', с: фазы[3].с, длит: фазы[3].длит, строки: итог, подписи: подписиИтога, край: краяИтога, стрелки: стрелкиИтога, подвал: подвалИтога
    });

    // Порядок по времени; при равенстве — как добавлено (сортировка в node устойчивая).
    шаги.sort(function (а, б) { return а.с - б.с; });
    разложитьСчёт(счёт, шаги);
    return {
      раунд: вход.раунд,
      всегоМс: всегоМс,
      фазы: фазы.map(function (ф) { return { имя: ф.имя, с: ф.с, длит: ф.длит }; }),
      шаги: шаги,
      журнал: журнал,
      итог: итог,
      подвалИтога: подвалИтога,
      подписиИтога: подписиИтога,
      крайИтога: краяИтога,
      стрелкиИтога: стрелкиИтога,
      боёв: боёв,
      боёвВПачке: пачка
    };
  }

  const ЗахватРаскрытие = {
    ВСЕГО_МС: ВСЕГО_МС,
    ФАЗЫ: ФАЗЫ,
    БОЙ_МС: БОЙ_МС,
    ВНУТРИ_БОЯ: ВНУТРИ_БОЯ,
    НАЛИВ: НАЛИВ,
    ВЕДУЩИЙ: ВЕДУЩИЙ,
    построить: построить,
    // Причина одного боя по входу раскрытия (тот же вход, что у построить) — строка или null.
    причинаБоя: function (вход, событие) { return причинаБоя(собратьКонтекст(вход), событие); },
    строкаРавенства: строкаРавенства,
    родительный: родительный,
    винительный: винительный
  };

  if (typeof module !== 'undefined') module.exports = ЗахватРаскрытие;
  if (typeof window !== 'undefined') window.ЗахватРаскрытие = ЗахватРаскрытие;
})();
