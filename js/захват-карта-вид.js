// «Захват»: расчёт раскладки карты (этап В4). Из состояния партии получается точный список
// «какой кадр какого рисунка куда положить»; сами рисунки рисует только Кодекс (правило владельца).
// Код ничего не рисует сам: функция нарисовать() идёт по списку и зовёт только drawImage готовых
// картинок (плюс save, restore, setTransform, clearRect и свойство globalAlpha для наливания).
// Договор сборки — штаб/игры/первая-игра/графика.md, раздел 4.3 (7 пунктов), размеры — 4.2–4.5.
// Шайбы, значки и пилюли на холст не кладутся: здесь считаются только их МЕСТА для слоя узлов
// (этапы.md, 0.5.2). Загрузка картинок, наливание по времени, стрелки и зум — этап Г1.
// Файл знает только карты; Date, таймеров и случая в нём нет. В конце и window.ЗахватКартаВид, и module.exports.
(function () {
  'use strict';

  const Карты = (typeof window !== 'undefined' && window.ЗахватКарты)
    ? window.ЗахватКарты
    : require('./захват-карты.js');

  // Цвета по месту за столом (графика.md 3.1): место 1 — коралл … место 6 — роза; ничья область — дым.
  const ЦВЕТА = ['коралл', 'лазурь', 'янтарь', 'аметист', 'бирюза', 'роза'];
  const ДЫМ = 'дым';

  // Кадр соты (4.3): холст 288×328, шестиугольник 256×296 по центру; центр шестиугольника — (144, 164).
  const КАДР = { ширина: 288, высота: 328, центрX: 144, центрY: 164, сотаШирина: 256, сотаВысота: 296 };
  // Лёгкий лист вдвое меньше (4.2, №8–14): кадр 144×164, раскладка та же ×0,5. Остальные листы — те же.
  const КАДР_ЛЁГКИЙ = { ширина: 144, высота: 164 };

  // Море — плитка 512×512 (№30); на экране кладётся в полразмера (решение разработчика, см. отчёт В4).
  const МОРЕ = { сторона: 512, наЭкране: 256 };

  // Шайбы (№18, №19), значок (№20): размер кадра в листе и размер на экране.
  const ШАЙБА = { войск: { кадр: 192, экран: 26 }, столицы: { кадр: 256, экран: 32 } };
  const ЗНАЧОК = { кадр: 128, экран: 12 };

  // Порядок слоёв снизу вверх (4.3). Стрелки — место в порядке, расчёт стрелок — Г1.
  const СЛОИ = ['море', 'тела', 'кромки', 'границы-краёв', 'выбор', 'цели', 'стрелки'];

  // Шесть граней (4.3): номер, имя и на сколько сдвинуться [ряд, столбец] к соседу для чётного
  // и для сдвинутого (нечётного) ряда — те же правила, что в js/захват-карты.js.
  const ГРАНИ = [
    { номер: 1, имя: 'верх-право', чётный: [-1, 0], сдвинутый: [-1, 1] },
    { номер: 2, имя: 'право', чётный: [0, 1], сдвинутый: [0, 1] },
    { номер: 3, имя: 'низ-право', чётный: [1, 0], сдвинутый: [1, 1] },
    { номер: 4, имя: 'низ-лево', чётный: [1, -1], сдвинутый: [1, 0] },
    { номер: 5, имя: 'лево', чётный: [0, -1], сдвинутый: [0, -1] },
    { номер: 6, имя: 'верх-лево', чётный: [-1, -1], сдвинутый: [-1, 0] }
  ];

  // Граница края ставится со стороны соты, у которой сосед справа, справа снизу или слева снизу (4.3 п.4):
  // грань -> номер кадра в граница-края.webp (0 право, 1 низ-право, 2 низ-лево).
  const КАДР_ГРАНИЦЫ_КРАЯ = { 2: 0, 3: 1, 4: 2 };

  function картаПартии(партия) {
    const карта = Карты.КАРТЫ[партия.карта] || (Карты.ТЕСТОВЫЕ && Карты.ТЕСТОВЫЕ[партия.карта]);
    if (!карта) throw new Error('Нет такой карты: ' + партия.карта);
    return карта;
  }

  // Размеры и место клеток для карты шириной в ширинаКарты пикселей (4.3 п.1; ТЗ 8.4.1:
  // ширина соты = ширина карты / (столбцов + 0,5)). Шаг по вертикали — 0,75 высоты соты.
  function геометрия(карта, ширинаКарты) {
    const ширинаСоты = ширинаКарты / (карта.столбцов + 0.5);
    const высотаСоты = ширинаСоты * КАДР.сотаВысота / КАДР.сотаШирина;
    const шагРяда = 0.75 * высотаСоты;
    return {
      ширинаСоты: ширинаСоты,
      высотаСоты: высотаСоты,
      шагРяда: шагРяда,
      масштаб: ширинаСоты / КАДР.сотаШирина,
      ширина: ширинаКарты,
      высота: высотаСоты + шагРяда * (карта.рядов - 1),
      // Центр клетки: нечётные ряды сдвинуты на полсоты вправо.
      центр: function (ряд, стб) {
        return {
          x: ширинаСоты * (стб + 0.5 + (ряд % 2 === 1 ? 0.5 : 0)),
          y: высотаСоты / 2 + ряд * шагРяда
        };
      }
    };
  }

  // Сетка карты -> двумерный массив номеров областей (0 — море).
  function полеОбластей(карта) {
    return карта.сетка.map(function (строка) {
      return строка.split(' ').map(function (буква) { return Карты.номерПоБукве(буква); });
    });
  }

  function областьВКлетке(поле, ряд, стб) {
    return (поле[ряд] && поле[ряд][стб]) || 0;
  }

  // Клетка за гранью; грань — объект из ГРАНИ.
  function заГранью(ряд, стб, грань) {
    const сдвиг = ряд % 2 === 1 ? грань.сдвинутый : грань.чётный;
    return { ряд: ряд + сдвиг[0], стб: стб + сдвиг[1] };
  }

  // Какого цвета область: по месту хозяина за столом; ничья — дым. Хозяина нет среди мест — ошибка,
  // а не молчаливый дым: иначе чужой цвет выглядел бы как ничья область.
  function цветХозяина(партия, хозяин) {
    if (хозяин === null || хозяин === undefined) return ДЫМ;
    const место = партия.игроки.indexOf(хозяин);
    if (место === -1 || место >= ЦВЕТА.length) throw new Error('У хозяина «' + хозяин + '» нет места за столом');
    return ЦВЕТА[место];
  }

  // Номер кадра цвета в листах шайб (цвета 3.1 по порядку, дым последний).
  function номерЦвета(цвет) {
    return цвет === ДЫМ ? ЦВЕТА.length : ЦВЕТА.indexOf(цвет);
  }

  // Прямоугольник кадра соты на экране: центр шестиугольника кадра (144, 164) ложится в центр клетки.
  function местоКадраСоты(г, ряд, стб) {
    const ц = г.центр(ряд, стб);
    return {
      x: ц.x - КАДР.центрX * г.масштаб,
      y: ц.y - КАДР.центрY * г.масштаб,
      ширина: КАДР.ширина * г.масштаб,
      высота: КАДР.высота * г.масштаб
    };
  }

  function источникКадра(номерКадра, ширина, высота) {
    return { x: номерКадра * ширина, y: 0, ширина: ширина, высота: высота };
  }

  function элемент(слой, рисунок, номерКадра, источник, куда, ряд, стб, область, грань) {
    return {
      слой: слой, рисунок: рисунок, кадр: номерКадра, источник: источник, куда: куда,
      ряд: ряд, стб: стб, область: область, грань: грань, альфа: 1
    };
  }

  // Плитки моря поверх прямоугольника поля (по умолчанию — вся карта). Плитки лежат по сетке с началом
  // в (0, 0), шов совпадает; крайние плитки обрезаются по полю (берётся часть рисунка).
  function плиткиМоря(поле) {
    const сторона = МОРЕ.наЭкране;
    const доля = МОРЕ.сторона / сторона;
    const список = [];
    const правый = поле.x + поле.ширина;
    const нижний = поле.y + поле.высота;
    for (let ряд = Math.floor(поле.y / сторона); ряд * сторона < нижний; ряд++) {
      for (let стб = Math.floor(поле.x / сторона); стб * сторона < правый; стб++) {
        const x0 = Math.max(стб * сторона, поле.x);
        const y0 = Math.max(ряд * сторона, поле.y);
        const x1 = Math.min((стб + 1) * сторона, правый);
        const y1 = Math.min((ряд + 1) * сторона, нижний);
        const источник = {
          x: (x0 - стб * сторона) * доля,
          y: (y0 - ряд * сторона) * доля,
          ширина: (x1 - x0) * доля,
          высота: (y1 - y0) * доля
        };
        const куда = { x: x0, y: y0, ширина: x1 - x0, высота: y1 - y0 };
        список.push(элемент('море', 'море-плитка', 0, источник, куда, null, null, null, null));
      }
    }
    return список;
  }

  // Центральная сота области: ближайшая к среднему центров её сот (ТЗ 8.4.1). Равенство — первая по
  // порядку «ряд за рядом, слева направо»: порядок один, поэтому шайба не прыгает от раунда к раунду.
  function центральныеСоты(карта, поле, г) {
    const сборка = {};
    поле.forEach(function (строка, ряд) {
      строка.forEach(function (номер, стб) {
        if (!номер) return;
        const ц = г.центр(ряд, стб);
        if (!сборка[номер]) сборка[номер] = { сумX: 0, сумY: 0, соты: [] };
        сборка[номер].сумX += ц.x;
        сборка[номер].сумY += ц.y;
        сборка[номер].соты.push({ ряд: ряд, стб: стб, x: ц.x, y: ц.y });
      });
    });
    const итог = {};
    Object.keys(сборка).forEach(function (номер) {
      const о = сборка[номер];
      const среднееX = о.сумX / о.соты.length;
      const среднееY = о.сумY / о.соты.length;
      let лучшая = null;
      let лучшееРасстояние = Infinity;
      о.соты.forEach(function (с) {
        const р = (с.x - среднееX) * (с.x - среднееX) + (с.y - среднееY) * (с.y - среднееY);
        // Допуск на шум дробных чисел: настоящее равенство расстояний не должно решаться девятым знаком.
        if (р < лучшееРасстояние - 1e-6) { лучшееРасстояние = р; лучшая = с; }
      });
      итог[номер] = лучшая;
    });
    return итог;
  }

  // Значок у верхнего правого края шайбы: его центр лежит на окружности шайбы под углом 45° вправо-вверх
  // (решение разработчика: в графике.md сказано только «у верхнего правого края»).
  function местоЗначка(х, у, размерШайбы, цвет) {
    const сдвиг = размерШайбы / 2 * Math.SQRT1_2;
    return {
      рисунок: 'значки',
      кадр: номерЦвета(цвет),
      размер: ЗНАЧОК.экран,
      x: х + сдвиг,
      y: у - сдвиг
    };
  }

  // Шайба области для слоя узлов (на холст не кладётся). Столица хозяина — гранёная шайба из шайбы-столиц.webp
  // со значком; у ничьей столицы шестицветного кадра нет (в листе 6 цветов игроков), поэтому она остаётся
  // шайбой войск цвета «дым» с отметкой столица: true.
  function собратьШайбу(партия, область, сота, значкиНаВсех) {
    const хозяин = партия.хозяева[область] === undefined ? null : партия.хозяева[область];
    const цвет = цветХозяина(партия, хозяин);
    const столица = (партия.столицы || []).some(function (с) { return с.область === область; });
    const гранёная = столица && хозяин !== null;
    const размер = гранёная ? ШАЙБА.столицы.экран : ШАЙБА.войск.экран;
    const шайба = {
      область: область,
      ряд: сота.ряд,
      стб: сота.стб,
      x: сота.x,
      y: сота.y,
      хозяин: хозяин,
      цвет: цвет,
      столица: столица,
      рисунок: гранёная ? 'шайбы-столиц' : 'шайбы',
      кадр: номерЦвета(цвет),
      размер: размер,
      значок: null
    };
    if (хозяин !== null && (гранёная || значкиНаВсех)) шайба.значок = местоЗначка(сота.x, сота.y, размер, цвет);
    return шайба;
  }

  // Внешние грани области: те, за которыми другая область или море (или край карты).
  function внешниеГрани(поле, ряд, стб, номер) {
    return ГРАНИ.filter(function (г) {
      const за = заГранью(ряд, стб, г);
      return областьВКлетке(поле, за.ряд, за.стб) !== номер;
    });
  }

  // Главная функция: состояние партии -> раскладка.
  // параметры: ширина — ширина карты в пикселях (обязательна); лёгкий — лист «-лёгкая» (4.4);
  //   выбрана — номер выбранной области или null; цели — номера допустимых целей;
  //   значкиНаВсех — значок хозяина на каждой шайбе (ТЗ 10); поле — {x, y, ширина, высота}, где лежит
  //   море (по умолчанию вся карта; при зуме экран просит больше).
  // Отдаёт { слои: {имя: [элементы]}, список: все элементы снизу вверх, шайбы, пилюли, геометрия }.
  function собратьРаскладку(партия, параметры) {
    const настройки = параметры || {};
    if (!(настройки.ширина > 0)) throw new Error('Не задана ширина карты');
    if (!партия || !Array.isArray(партия.хозяева)) throw new Error('В партии нет списка хозяев областей (партия.хозяева)');
    if (!Array.isArray(партия.игроки)) throw new Error('В партии нет списка мест за столом (партия.игроки)');
    const карта = картаПартии(партия);
    const г = геометрия(карта, настройки.ширина);
    const поле = полеОбластей(карта);
    const лёгкий = !!настройки.лёгкий;
    const кадрСоты = лёгкий ? КАДР_ЛЁГКИЙ : КАДР;
    // Цели без повторов и без выбранной области: иначе контур лёг бы дважды (в «выбор» и в «цели»).
    const цели = (настройки.цели || []).filter(function (номер, и, все) {
      return номер !== настройки.выбрана && все.indexOf(номер) === и;
    });
    const слои = {};
    СЛОИ.forEach(function (имя) { слои[имя] = []; });

    слои['море'] = плиткиМоря(настройки.поле || { x: 0, y: 0, ширина: г.ширина, высота: г.высота });

    // Номер края области: для границы края (4.3 п.4); у моря края нет.
    const крайОбласти = {};
    карта.области.forEach(function (о) { крайОбласти[о.номер] = о.край; });

    поле.forEach(function (строка, ряд) {
      строка.forEach(function (номер, стб) {
        if (!номер) return;
        const куда = местоКадраСоты(г, ряд, стб);
        const лист = 'сота-' + цветХозяина(партия, партия.хозяева[номер]) + (лёгкий ? '-лёгкая' : '');
        // 4.3 п.2: на каждую клетку — кадр 0 (тело) листа цвета хозяина.
        слои['тела'].push(элемент('тела', лист, 0, источникКадра(0, кадрСоты.ширина, кадрСоты.высота),
          куда, ряд, стб, номер, null));
        ГРАНИ.forEach(function (грань) {
          const за = заГранью(ряд, стб, грань);
          const соседняя = областьВКлетке(поле, за.ряд, за.стб);
          // 4.3 п.3: грань, за которой другая область или море, — кромка этой грани того же листа.
          if (соседняя !== номер) {
            слои['кромки'].push(элемент('кромки', лист, грань.номер,
              источникКадра(грань.номер, кадрСоты.ширина, кадрСоты.высота), куда, ряд, стб, номер, грань.номер));
          }
          // 4.3 п.4: граница края — только между областями разных краёв и только с трёх сторон.
          const кадрГраницы = КАДР_ГРАНИЦЫ_КРАЯ[грань.номер];
          if (кадрГраницы !== undefined && соседняя && соседняя !== номер &&
              крайОбласти[соседняя] !== крайОбласти[номер]) {
            слои['границы-краёв'].push(элемент('границы-краёв', 'граница-края', кадрГраницы,
              источникКадра(кадрГраницы, КАДР.ширина, КАДР.высота), куда, ряд, стб, номер, грань.номер));
          }
        });
      });
    });

    // 4.3 п.6: выбор и цели — на внешние грани области, кадр = номер грани − 1.
    function контур(слой, рисунок, номер) {
      поле.forEach(function (строка, ряд) {
        строка.forEach(function (н, стб) {
          if (н !== номер) return;
          const куда = местоКадраСоты(г, ряд, стб);
          внешниеГрани(поле, ряд, стб, номер).forEach(function (грань) {
            слои[слой].push(элемент(слой, рисунок, грань.номер - 1,
              источникКадра(грань.номер - 1, КАДР.ширина, КАДР.высота), куда, ряд, стб, номер, грань.номер));
          });
        });
      });
    }
    if (настройки.выбрана) контур('выбор', 'выбор', настройки.выбрана);
    цели.forEach(function (номер) { контур('цели', 'цели', номер); });

    // 4.3 п.5: шайба — на центральной соте каждой области. Пилюля «+N» — над шайбой: даём якорь
    // (середина верха шайбы), подгонку по высоте пилюли делает слой узлов.
    const центры = центральныеСоты(карта, поле, г);
    const шайбы = [];
    const пилюли = [];
    карта.области.forEach(function (о) {
      const сота = центры[о.номер];
      if (!сота) return;
      const шайба = собратьШайбу(партия, о.номер, сота, !!настройки.значкиНаВсех);
      шайбы.push(шайба);
      пилюли.push({ область: о.номер, x: шайба.x, y: шайба.y - шайба.размер / 2 });
    });

    const список = [];
    СЛОИ.forEach(function (имя) {
      слои[имя].forEach(function (э) { список.push(э); });
    });
    return { карта: карта.ключ, лёгкий: лёгкий, геометрия: г, слои: слои, список: список, шайбы: шайбы, пилюли: пилюли };
  }

  // Рисование: проходит по списку и зовёт ТОЛЬКО drawImage готовых картинок. картинки — {имя рисунка: картинка}.
  // Нет картинки — элемент пропускается и попадает в «нет»: заглушек код не рисует. Холст перед
  // рисованием очищается; зум и сдвиг — через setTransform (разрешённое преобразование).
  // параметры: ширинаХолста, высотаХолста (в пикселях холста), зум (1), сдвигX, сдвигY (0).
  function нарисовать(ctx, раскладка, картинки, параметры) {
    const п = параметры || {};
    const зум = п.зум || 1;
    const нет = {};
    let нарисовано = 0;
    ctx.save();
    ctx.setTransform(1, 0, 0, 1, 0, 0);
    ctx.clearRect(0, 0, п.ширинаХолста || раскладка.геометрия.ширина, п.высотаХолста || раскладка.геометрия.высота);
    ctx.setTransform(зум, 0, 0, зум, п.сдвигX || 0, п.сдвигY || 0);
    раскладка.список.forEach(function (э) {
      const картинка = картинки && картинки[э.рисунок];
      if (!картинка) { нет[э.рисунок] = true; return; }
      // Прозрачность ставится только у «наливающихся» сот (альфа < 1) и сразу возвращается.
      if (э.альфа !== 1) ctx.globalAlpha = э.альфа;
      ctx.drawImage(картинка, э.источник.x, э.источник.y, э.источник.ширина, э.источник.высота,
        э.куда.x, э.куда.y, э.куда.ширина, э.куда.высота);
      if (э.альфа !== 1) ctx.globalAlpha = 1;
      нарисовано++;
    });
    ctx.restore();
    return { нарисовано: нарисовано, нет: Object.keys(нет) };
  }

  const ЗахватКартаВид = {
    ЦВЕТА: ЦВЕТА,
    ДЫМ: ДЫМ,
    КАДР: КАДР,
    КАДР_ЛЁГКИЙ: КАДР_ЛЁГКИЙ,
    МОРЕ: МОРЕ,
    ШАЙБА: ШАЙБА,
    ЗНАЧОК: ЗНАЧОК,
    СЛОИ: СЛОИ,
    ГРАНИ: ГРАНИ,
    геометрия: геометрия,
    цветХозяина: цветХозяина,
    собратьРаскладку: собратьРаскладку,
    нарисовать: нарисовать
  };

  if (typeof module !== 'undefined') module.exports = ЗахватКартаВид;
  if (typeof window !== 'undefined') window.ЗахватКартаВид = ЗахватКартаВид;
})();
