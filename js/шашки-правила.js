/** Запомнить, что такая позиция на доске уже была. */
function запомнитьПозицию(партия) {
  партия.былиПозиции.push(отпечатокПозиции(партия));
}

/** Сколько раз уже встречалась нынешняя позиция (считая её саму). */
function встреченоРаз(партия) {
  const отпечаток = отпечатокПозиции(партия);
  let сколько = 0;
  for (let i = 0; i < партия.былиПозиции.length; i++) {
    if (партия.былиПозиции[i] === отпечаток) сколько++;
  }
  return сколько;
}

/* Соотношение сил «три дамки (и больше) против одной дамки»
   [1, ст. 7.2.4], [2]. Простых при этом нет ни у кого — правило писано
   именно про дамочное окончание. */
function триДамкиПротивОдной(партия) {
  const белые = сколькоФишек(партия, БЕЛЫЕ);
  const чёрные = сколькоФишек(партия, ЧЁРНЫЕ);
  function перевес(сильные, слабые) {
    return сильные.простые === 0 && сильные.дамки >= 3 &&
           слабые.простые === 0 && слабые.дамки === 1;
  }
  return перевес(белые, чёрные) || перевес(чёрные, белые);
}

/** Пересчитать счётчики ничейных правил после сделанного хода. */
function обновитьСчётчикиНичьих(партия, ход, ходилаПростая) {
  // Взятие или ход простой обнуляют «15 ходов только дамками».
  партия.тихихХодовДамками = (ход.бой || ходилаПростая) ? 0 : партия.тихихХодовДамками + 1;
  // Счётчик трёх дамок идёт, только пока такое соотношение на доске.
  партия.полуходовПриТрёхДамках = триДамкиПротивОдной(партия)
    ? партия.полуходовПриТрёхДамках + 1
    : 0;
}

function записатьИтог(партия, результат, причина) {
  партия.завершена = true;
  партия.результат = результат;
  партия.причина = причина;
}

/* Падежи цвета — чтобы причина окончания читалась по-русски,
   а не «у белые не осталось шашек». */
function кому(цвет) { return цвет === БЕЛЫЕ ? 'белым' : 'чёрным'; }
function укого(цвет) { return цвет === БЕЛЫЕ ? 'белых' : 'чёрных'; }

/**
 * Кончилась ли партия.
 *
 * Проигрывает тот, кому нечем ходить: либо шашек не осталось, либо все
 * заперты [1, ст. 6.1.2 и 6.1.3], [2]. Это именно проигрыш, а не ничья —
 * место, где легко ошибиться, если писать по статье про другие шашки.
 *
 * Ничьи берём три автоматических: повторение позиции трижды, пятнадцать
 * ходов одними дамками и три дамки против одной. Остальные пункты
 * спортивных правил (5/30/60 ходов в малофигурных окончаниях, «одинокая
 * дамка на большой дороге») писаны для судьи с бланком, срабатывают
 * редко и путают новичка — решение штаба, записано в план-шашек.md,
 * раздел 4, «спорное место 4».
 */
function проверитьКонец(партия) {
  if (партия.завершена) return;
  if (собратьХоды(партия).length === 0) {
    const счёт = сколькоФишек(партия, партия.ходит);
    записатьИтог(партия, соперник(партия.ходит), счёт.всего === 0
      ? 'у ' + укого(партия.ходит) + ' не осталось шашек'
      : кому(партия.ходит) + ' нечем ходить: все шашки заперты');
    return;
  }
  if (встреченоРаз(партия) >= ПОВТОРОВ_ДО_НИЧЬЕЙ) {
    записатьИтог(партия, 'ничья', 'одна и та же позиция повторилась три раза');
    return;
  }
  if (партия.тихихХодовДамками >= ПОЛУХОДОВ_ТОЛЬКО_ДАМКАМИ) {
    записатьИтог(партия, 'ничья',
      'пятнадцать ходов подряд двигались только дамки: ни взятий, ни ходов простыми');
    return;
  }
  if (партия.полуходовПриТрёхДамках >= ПОЛУХОДОВ_ТРИ_ДАМКИ_ПРОТИВ_ОДНОЙ) {
    записатьИтог(партия, 'ничья',
      'три дамки против одной за пятнадцать ходов не взяли дамку соперника');
  }
}

/** Кончилась ли партия. */
function партияЗавершена(партия) {
  return партия.завершена;
}

/**
 * Итог партии или null, если она ещё идёт:
 *   { победитель: 'белые' | 'чёрные' | null, ничья: true|false, причина: '…' }
 */
function итог(партия) {
  if (!партия.завершена) return null;
  const ничья = партия.результат === 'ничья';
  return {
    победитель: ничья ? null : партия.результат,
    ничья: ничья,
    причина: партия.причина
  };
}

