/* =====================================================================
   ЧАСТЬ 1. ДОСКА И КЛЕТКИ
   ===================================================================== */

/* Клетки нумеруем числами от 0 до 63: номер = ряд * 8 + столбец.
   Ряд 0 — это первая горизонталь (там начинают белые), ряд 7 — восьмая.
   Столбец 0 — вертикаль «a», столбец 7 — вертикаль «h».

   Наружу номера не выходят вовсе: снаружи поля называются по-человечески
   («e3», «h8»). Числа остались внутри просто потому, что доску удобно
   держать одним плоским списком: такой список копируется одной строчкой
   и сравнивается целиком — а копировать и сравнивать позицию придётся
   очень часто (боту при переборе, проверке — при поиске повторений). */
const БУКВЫ = 'abcdefgh';
const РЯДОВ = 8;
const СТОЛБЦОВ = 8;

/** Номер клетки по ряду и столбцу. За доской — минус единица. */
function клетка(ряд, столбец) {
  if (ряд < 0 || ряд >= РЯДОВ || столбец < 0 || столбец >= СТОЛБЦОВ) return -1;
  return ряд * СТОЛБЦОВ + столбец;
}

function рядКлетки(номер) { return Math.floor(номер / СТОЛБЦОВ); }
function столбецКлетки(номер) { return номер % СТОЛБЦОВ; }

/** Человеческое имя клетки: 0 → 'a1', 63 → 'h8'. */
function имяКлетки(номер) {
  return БУКВЫ[столбецКлетки(номер)] + (рядКлетки(номер) + 1);
}

/** Номер клетки по имени. Мусор и светлые поля дают минус единицу. */
function номерКлетки(имя) {
  if (typeof имя !== 'string' || имя.length !== 2) return -1;
  const столбец = БУКВЫ.indexOf(имя[0].toLowerCase());
  const ряд = имя.charCodeAt(1) - 49;      // символ '1' имеет код 49
  const номер = клетка(ряд, столбец);
  if (номер === -1 || !играющая(номер)) return -1;
  return номер;
}

/* Играют только по тёмным полям. Доска ставится так, чтобы слева от
   каждого игрока было тёмное угловое поле [1, ст. 2.1.4], — значит,
   поле a1 тёмное, и тёмными оказываются все клетки, у которых сумма
   ряда и столбца чётная. */
function играющая(номер) {
  return (рядКлетки(номер) + столбецКлетки(номер)) % 2 === 0;
}

/* Все 32 игровых поля по порядку — от a1 к h8. Экрану и проверкам
   удобно обходить доску по этому списку и не думать про светлые поля. */
const ПОЛЯ = (function () {
  const список = [];
  for (let н = 0; н < РЯДОВ * СТОЛБЦОВ; н++) if (играющая(н)) список.push(имяКлетки(н));
  return список;
})();

/* Четыре диагональных направления. Шашки ходят только по ним. */
const ШАГИ = [
  { дряд: 1, дстолбец: 1 },     // вправо-вверх
  { дряд: 1, дстолбец: -1 },    // влево-вверх
  { дряд: -1, дстолбец: 1 },    // вправо-вниз
  { дряд: -1, дстолбец: -1 }    // влево-вниз
];

/* =====================================================================
   ЧАСТЬ 2. ФИШКИ
   ===================================================================== */

/* Что лежит в клетке доски. Держим маленькими числами, а не объектами:
   доска из чисел копируется одним .slice(), а два объекта пришлось бы
   обходить по одному и сравнивать вручную. Читаемость от этого не
   страдает — снаружи числа не видны, а внутри есть два вопроса-функции:
   «какого цвета фишка» и «дамка ли она». */
const ПУСТО = 0;
const БЕЛАЯ_ПРОСТАЯ = 1;
const БЕЛАЯ_ДАМКА = 2;
const ЧЁРНАЯ_ПРОСТАЯ = 3;
const ЧЁРНАЯ_ДАМКА = 4;

const БЕЛЫЕ = 'белые';
const ЧЁРНЫЕ = 'чёрные';

/** Цвет фишки: 'белые', 'чёрные' или null, если клетка пуста. */
function цветФишки(фишка) {
  if (фишка === БЕЛАЯ_ПРОСТАЯ || фишка === БЕЛАЯ_ДАМКА) return БЕЛЫЕ;
  if (фишка === ЧЁРНАЯ_ПРОСТАЯ || фишка === ЧЁРНАЯ_ДАМКА) return ЧЁРНЫЕ;
  return null;
}

/** Дамка ли это. Пустая клетка — не дамка. */
function этоДамка(фишка) {
  return фишка === БЕЛАЯ_ДАМКА || фишка === ЧЁРНАЯ_ДАМКА;
}

function простаяЦвета(цвет) { return цвет === БЕЛЫЕ ? БЕЛАЯ_ПРОСТАЯ : ЧЁРНАЯ_ПРОСТАЯ; }
function дамкаЦвета(цвет) { return цвет === БЕЛЫЕ ? БЕЛАЯ_ДАМКА : ЧЁРНАЯ_ДАМКА; }
function соперник(цвет) { return цвет === БЕЛЫЕ ? ЧЁРНЫЕ : БЕЛЫЕ; }

/* Куда для этого цвета «вперёд». Белые идут вверх (ряд растёт),
   чёрные — вниз. Нужно только простым: дамке всё равно. */
function вперёдДля(цвет) { return цвет === БЕЛЫЕ ? 1 : -1; }

/* Последняя горизонталь — та, дойдя до которой простая становится дамкой
   [1, ст. 3.6]: для белых восьмая (ряд 7), для чёрных первая (ряд 0). */
function последняяГоризонталь(номер, цвет) {
  return цвет === БЕЛЫЕ ? рядКлетки(номер) === РЯДОВ - 1 : рядКлетки(номер) === 0;
}

/* Знаки для картинки доски. Одна буква — одна фишка, заглавная — дамка.
   Эти же знаки идут в отпечаток позиции, по которому ловятся повторения. */
const ЗНАКИ = { 0: '.', 1: 'б', 2: 'Б', 3: 'ч', 4: 'Ч' };
const ФИШКА_ПО_ЗНАКУ = { 'б': БЕЛАЯ_ПРОСТАЯ, 'Б': БЕЛАЯ_ДАМКА, 'ч': ЧЁРНАЯ_ПРОСТАЯ, 'Ч': ЧЁРНАЯ_ДАМКА };

/* =====================================================================
   ЧАСТЬ 3. СОСТОЯНИЕ ПАРТИИ

   Партия — обычные данные: списки, числа и строки. Никаких функций
   и ссылок на живые объекты внутри нет. Поэтому её можно скопировать,
   сравнить целиком и (когда дойдёт до сервера) отправить по сети.
   ===================================================================== */

/* Сколько раз должна повториться одна и та же позиция, чтобы объявить
   ничью. Позиция считается той же, если и расстановка та же, и ход
   принадлежит тому же игроку [1, ст. 7.2.3], [2]. */
const ПОВТОРОВ_ДО_НИЧЬЕЙ = 3;

/* «Если в течение 15 ходов игроки делали ходы только дамками, не
   передвигая простых шашек и не производя взятия» [2], [1, ст. 7.2.5].
   Слово «ход» в правилах шашек значит ход ОБЕИХ сторон, поэтому внутри
   считаем полуходами: 15 ходов = 30 полуходов. */
const ПОЛУХОДОВ_ТОЛЬКО_ДАМКАМИ = 30;

/* «Участник, имеющий три дамки (и более) против одной дамки противника,
   за 15 ходов не возьмёт дамку противника» [2], [1, ст. 7.2.4].
   Считаем так же, полуходами с того мгновения, как такое соотношение
   сложилось. */
const ПОЛУХОДОВ_ТРИ_ДАМКИ_ПРОТИВ_ОДНОЙ = 30;

/**
 * Пустая заготовка партии. Доска приходит готовой, остальное —
 * начальные значения счётчиков.
 */
function собратьПартию(доска, ктоХодит) {
  const партия = {
    доска: доска,                 // 64 клетки; светлые всегда пустые
    ходит: ктоХодит,              // 'белые' или 'чёрные'
    завершена: false,
    результат: null,              // 'белые', 'чёрные' или 'ничья'
    причина: null,                // почему кончилась — человеческими словами
    номерХода: 1,                 // номер полного хода, как в записи партии
    полуходов: 0,                 // сколько ходов сделано всего, по одному на игрока
    /* Счётчик правила «15 ходов только дамками». Обнуляется взятием
       и любым ходом простой. */
    тихихХодовДамками: 0,
    /* Счётчик правила «три дамки против одной». Обнуляется, как только
       такое соотношение сил перестало быть на доске. */
    полуходовПриТрёхДамках: 0,
    /* Все позиции, которые уже были в этой партии, по порядку — простым
       списком отпечатков. Держим внутри партии нарочно: иначе правило
       про троекратное повторение пришлось бы пересказывать снаружи.

       Почему СПИСОК, а не словарь «отпечаток → сколько раз». Словарь
       казался умнее, но замер показал засаду: как только в нём набирается
       больше двух десятков ключей, копирование такого объекта дорожает
       разом в двести раз (0,04 микросекунды против 11). А копировать
       партию приходится на каждом шаге перебора у бота — и на тридцатом
       ходу он начинал думать втрое медленнее, чем на десятом, ровно из-за
       этой строчки. Список копируется одним slice за 0,04 микросекунды
       и не проваливается никогда; пересчитывать повторы по нему дороже,
       но это делается один раз за ход, а не на каждом шаге перебора. */
    былиПозиции: []
  };
  запомнитьПозицию(партия);
  проверитьКонец(партия);
  return партия;
}

/**
 * Новая партия: доска 8×8, по 12 шашек, первые три горизонтали у белых
 * и последние три у чёрных, ряды 4 и 5 пустые. Первый ход всегда белых
 * [1, ст. 3.3], [2].
 */
function создатьПартию() {
  const доска = new Array(РЯДОВ * СТОЛБЦОВ).fill(ПУСТО);
  for (let н = 0; н < доска.length; н++) {
    if (!играющая(н)) continue;
    const ряд = рядКлетки(н);
    if (ряд <= 2) доска[н] = БЕЛАЯ_ПРОСТАЯ;
    if (ряд >= РЯДОВ - 3) доска[н] = ЧЁРНАЯ_ПРОСТАЯ;
  }
  return собратьПартию(доска, БЕЛЫЕ);
}

/**
 * Партия из картинки — восьми строк по восемь знаков. Верхняя строка —
 * восьмая горизонталь, как человек видит доску со стороны белых.
 *
 *   'б' белая простая, 'Б' белая дамка,
 *   'ч' чёрная простая, 'Ч' чёрная дамка,
 *   '.' или пробел — пусто.
 *
 * Нужна для позиций-ловушек: правило проще один раз нарисовать, чем
 * описывать словами. Картинку можно передать и одной строкой с
 * переносами. Кривая картинка — это ошибка с понятным текстом, а не
 * тихо испорченная доска: молчаливая ошибка тут дороже громкой.
 */
function партияИзКартинки(картинка, ктоХодит) {
  /* Картинку берём как есть: пробел — это пустое поле, и подрезать
     строки нельзя, иначе пропадут пустые клетки слева. Поэтому строкой
     картинку пишут без отступов, ровно по восемь знаков в строке. */
  const строки = Array.isArray(картинка)
    ? картинка.slice()
    : String(картинка).replace(/\r/g, '').split('\n').filter(function (с) { return с.length > 0; });
  if (строки.length !== РЯДОВ) {
    throw new Error('В картинке доски должно быть ровно 8 строк, а пришло ' + строки.length);
  }
  const доска = new Array(РЯДОВ * СТОЛБЦОВ).fill(ПУСТО);
  for (let i = 0; i < РЯДОВ; i++) {
    const строка = строки[i];
    if (строка.length !== СТОЛБЦОВ) {
      throw new Error('В строке «' + строка + '» должно быть ровно 8 знаков');
    }
    const ряд = РЯДОВ - 1 - i;             // верхняя строка картинки — восьмая горизонталь
    for (let столбец = 0; столбец < СТОЛБЦОВ; столбец++) {
      const знак = строка[столбец];
      if (знак === '.' || знак === ' ') continue;
      const фишка = ФИШКА_ПО_ЗНАКУ[знак];
      if (фишка === undefined) throw new Error('Непонятный знак «' + знак + '» в картинке доски');
      const номер = клетка(ряд, столбец);
      if (!играющая(номер)) {
        throw new Error('Фишка на светлом поле ' + имяКлетки(номер) + ' — играют только по тёмным');
      }
      доска[номер] = фишка;
    }
  }
  const цвет = ктоХодит === ЧЁРНЫЕ ? ЧЁРНЫЕ : БЕЛЫЕ;
  return собратьПартию(доска, цвет);
}

/** Доска словами: восемь строк, верхняя — восьмая горизонталь. */
function картинкаПартии(партия) {
  const строки = [];
  for (let ряд = РЯДОВ - 1; ряд >= 0; ряд--) {
    let строка = '';
    for (let столбец = 0; столбец < СТОЛБЦОВ; столбец++) {
      const номер = клетка(ряд, столбец);
      строка += играющая(номер) ? ЗНАКИ[партия.доска[номер]] : ' ';
    }
    строки.push(строка);
  }
  return строки;
}

/** Независимая копия партии: менять её можно как угодно, оригинал цел. */
function копияПартии(партия) {
  return {
    доска: партия.доска.slice(),
    ходит: партия.ходит,
    завершена: партия.завершена,
    результат: партия.результат,
    причина: партия.причина,
    номерХода: партия.номерХода,
    полуходов: партия.полуходов,
    тихихХодовДамками: партия.тихихХодовДамками,
    полуходовПриТрёхДамках: партия.полуходовПриТрёхДамках,
    былиПозиции: партия.былиПозиции.slice()
  };
}

/** Что стоит на поле: { цвет, дамка } или null, если пусто. */
function фишка(партия, поле) {
  const номер = номерКлетки(поле);
  if (номер === -1) return null;
  const что = партия.доска[номер];
  if (что === ПУСТО) return null;
  return { цвет: цветФишки(что), дамка: этоДамка(что) };
}

/** Чей сейчас ход. */
function чейХод(партия) {
  return партия.ходит;
}

/** Сколько у цвета фишек: { простые, дамки, всего }. */
function сколькоФишек(партия, цвет) {
  let простые = 0;
  let дамки = 0;
  for (const что of партия.доска) {
    if (цветФишки(что) !== цвет) continue;
    if (этоДамка(что)) дамки++; else простые++;
  }
  return { простые: простые, дамки: дамки, всего: простые + дамки };
}

/**
 * Отпечаток позиции — короткая строка, по которой позиции сравниваются.
 * В неё входит расстановка по 32 игровым полям и чей ход: позиция та же
 * только тогда, когда и фишки те же, и ход принадлежит тому же игроку
 * [1, ст. 7.2.3].
 */
function отпечатокПозиции(партия) {
  let слепок = '';
  for (let н = 0; н < партия.доска.length; н++) {
    if (играющая(н)) слепок += ЗНАКИ[партия.доска[н]];
  }
  return слепок + '|' + (партия.ходит === БЕЛЫЕ ? 'б' : 'ч');
}

/* =====================================================================
   ЧАСТЬ 4. КАКИЕ ХОДЫ ВОЗМОЖНЫ

   Ход — это тоже обычные данные:
     { откуда, куда, бой, побитые, путь, станетДамкой }
   где «побитые» — имена полей снятых фишек по порядку взятия,
   а «путь» — все поля, на которые вставала фишка, начиная со стартового.

   Два списка идут в ногу, и на это можно опираться: в бою каждый прыжок
   снимает ровно одну фишку, поэтому «побитые[i]» снимается на переходе
   от «путь[i]» к «путь[i+1]», а длина пути всегда на единицу больше числа
   побитых. Экрану это нужно, чтобы вести цепочку по одному прыжку и
   показывать, кто уже побит, но ещё стоит на доске. Связь проверяется
   в самопроверке внизу файла — нарушим её однажды, узнаем сразу.
   ===================================================================== */

/**
 * Ключ хода: по нему ходы сравниваются и отсеиваются повторы.
 *
 * Признак «станет дамкой» входит в ключ не для красоты. Бывает так, что
 * простая снимает одни и те же фишки и встаёт на то же поле, но по одной
 * дороге успевает заглянуть на последнюю горизонталь и превращается,
 * а по другой — нет. На доске это ДВА РАЗНЫХ хода: после одного у игрока
 * дамка, после другого простая. Без этого признака игра теряла бы один
 * из них — как раз тот, ради которого русские шашки и отличаются от
 * остальных (проверено сверкой с чужим перебором, см. отчёт по этапу).
 */
function ключХода(ход) {
  return ход.откуда + '>' + ход.куда + ':' + ход.побитые.slice().sort().join(',') +
    (ход.станетДамкой ? '=дамка' : '');
}

/**
 * Все прыжки, которые фишка может сделать прямо сейчас из этой клетки.
 *
 * Тут живёт ТУРЕЦКИЙ УДАР [1, ст. 4.8, 4.11], [2]: побитые фишки
 * снимаются только в конце хода, поэтому по ходу цепочки они остаются
 * на доске. Через уже побитую нельзя ни бить второй раз, ни перелететь
 * дальше — она перекрывает дамке дорогу так же, как живая фишка.
 * Именно поэтому список «побитые» проверяется до всего остального.
 */
function прыжкиИзКлетки(доска, откуда, цвет, дамка, побитые) {
  const прыжки = [];
  const ряд = рядКлетки(откуда);
  const столбец = столбецКлетки(откуда);

  for (const шаг of ШАГИ) {
    // Ищем первую занятую клетку на луче. Простая смотрит только
    // на соседнюю, дамка скользит по пустым сколько угодно [1, ст. 4.2, 4.3].
    let р = ряд + шаг.дряд;
    let с = столбец + шаг.дстолбец;
    let жертва = -1;
    while (true) {
      const к = клетка(р, с);
      if (к === -1) break;
      if (доска[к] !== ПУСТО) { жертва = к; break; }
      if (!дамка) break;
      р += шаг.дряд;
      с += шаг.дстолбец;
    }
    if (жертва === -1) continue;
    if (цветФишки(доска[жертва]) === цвет) continue;          // через свою не бьют
    if (побитые.indexOf(имяКлетки(жертва)) !== -1) continue;  // уже побита — турецкий удар

    // Куда встать за побитой: простая — сразу за ней, дамка — на любое
    // свободное поле дальше по той же диагонали [1, ст. 4.3].
    let р2 = рядКлетки(жертва) + шаг.дряд;
    let с2 = столбецКлетки(жертва) + шаг.дстолбец;
    while (true) {
      const к2 = клетка(р2, с2);
      if (к2 === -1 || доска[к2] !== ПУСТО) break;
      прыжки.push({ жертва: жертва, куда: к2 });
      if (!дамка) break;
      р2 += шаг.дряд;
      с2 += шаг.дстолбец;
    }
  }
  return прыжки;
}

/**
 * Обойти все цепочки боя из этой клетки и сложить готовые ходы.
 *
 * Правило «бьёшь — доводи до конца» [1, ст. 4.5, 4.6] живёт здесь:
 * ход записывается ТОЛЬКО там, где продолжений больше нет. Поэтому
 * бросить цепочку посередине нельзя — такого хода просто не окажется
 * в списке возможных.
 *
 * СПОРНОЕ МЕСТО (превращение в дамку во время боя). В русских шашках
 * простая, приземлившаяся боем на последнюю горизонталь, становится
 * дамкой сразу, внутри хода, и продолжает бой уже по правилам дамки
 * [1, ст. 4.14], [2] («При бое через дамочное поле простая шашка
 * превращается в дамку и продолжает бой по правилам дамки»),
 * [3] («If a man touches the kings row during a capture and can continue
 * a capture, it jumps backwards as a king»). Поэтому признак «дамка»
 * ставится ДО поиска продолжений: иначе игра искала бы продолжения
 * по правилам простой и теряла законные ходы. В международных шашках
 * ответ противоположный, в английских ход вообще кончается — если
 * кто-то захочет «поправить» это место по чужой статье, пусть сначала
 * посмотрит, про какие она шашки [1, ст. 4.16.2 и 4.16.3].
 */
function искатьБои(доска, поле, цвет, дамка, стартоваяДамка, побитые, путь, ходы, ключи) {
  const прыжки = прыжкиИзКлетки(доска, поле, цвет, дамка, побитые);
  if (прыжки.length === 0) {
    if (побитые.length > 0) {
      добавитьХод(ходы, ключи, {
        откуда: путь[0],
        куда: путь[путь.length - 1],
        бой: true,
        побитые: побитые.slice(),
        путь: путь.slice(),
        станетДамкой: !стартоваяДамка && дамка
      });
    }
    return;
  }
  for (const прыжок of прыжки) {
    побитые.push(имяКлетки(прыжок.жертва));
    путь.push(имяКлетки(прыжок.куда));
    // Дошла боем до последней горизонтали — дальше бьёт уже дамкой.
    const теперьДамка = дамка || последняяГоризонталь(прыжок.куда, цвет);
    искатьБои(доска, прыжок.куда, цвет, теперьДамка, стартоваяДамка, побитые, путь, ходы, ключи);
    путь.pop();
    побитые.pop();
  }
}

/* Кладём ход в список, если такого ещё нет.

   Повторы бывают: фишку можно обвести по кольцу вокруг четырёх чужих
   шашек в одну сторону и в другую — снимутся те же четыре, и встанет
   она на то же место. На доске это ОДИН ход, и показывать его дважды
   значит врать про число возможностей.

   Знать про этот отсев полезно тому, кто будет сверять наши числа
   с чужими. Сверка уже сделана (перебор ходов из начальной позиции,
   эталон — Rein Halbersma, «Perft for all recognized draughts
   variants», damforum.nl/viewtopic.php?t=2822): на глубинах с 1 по 7
   наши числа совпали с эталоном в точности —
   7, 49, 302, 1469, 7482, 37986, 190146.
   На восьмом полуходе эталон даёт 929905, у нас 929901: разница —
   ровно шесть таких колец, найденных поимённо. Без отсева у нас
   получается 929907, то есть эталон лежит между нашими двумя числами.
   Расхождение не в правилах, а в том, считать ли кольцо одним ходом
   или двумя; мы считаем одним. */
function добавитьХод(ходы, ключи, ход) {
  const ключ = ключХода(ход);
  if (ключи[ключ]) return;
  ключи[ключ] = true;
  ходы.push(ход);
}

/** Тихие (без боя) ходы одной фишки. */
function тихиеХодыФишки(доска, откуда, цвет, дамка) {
  const ходы = [];
  const ряд = рядКлетки(откуда);
  const столбец = столбецКлетки(откуда);
  for (const шаг of ШАГИ) {
    // Простая ходит только вперёд [1, ст. 3.5], хотя бьёт и назад.
    if (!дамка && шаг.дряд !== вперёдДля(цвет)) continue;
    let р = ряд + шаг.дряд;
    let с = столбец + шаг.дстолбец;
    while (true) {
      const к = клетка(р, с);
      if (к === -1 || доска[к] !== ПУСТО) break;
      ходы.push({
        откуда: имяКлетки(откуда),
        куда: имяКлетки(к),
        бой: false,
        побитые: [],
        путь: [имяКлетки(откуда), имяКлетки(к)],
        станетДамкой: !дамка && последняяГоризонталь(к, цвет)
      });
      if (!дамка) break;      // простая шагает ровно на одну клетку
      р += шаг.дряд;
      с += шаг.дстолбец;
    }
  }
  return ходы;
}

/**
 * Все законные ходы того, чей сейчас ход. Здесь же держится главное
 * правило русских шашек: БОЙ ОБЯЗАТЕЛЕН [1, ст. 4.2], [2]. Есть чем
 * бить — тихих ходов в списке не будет вовсе.
 *
 * СПОРНОЕ МЕСТО (бить ли наибольшее количество). НЕТ. «При нескольких
 * вариантах взятия игрок выбирает вариант взятия по своему усмотрению»
 * [2]; то же дословно в [1, ст. 4.13] — «regardless of the number or
 * quality of pieces». Правило «бей максимум» — это международные шашки
 * и бразильская разновидность [1, ст. 4.16.1]; взять его сюда значит
 * сделать игру, которая выглядит правильной и врёт.
 */
function собратьХоды(партия) {
  const цвет = партия.ходит;
  const бои = [];
  const ключи = {};
  for (let н = 0; н < партия.доска.length; н++) {
    if (цветФишки(партия.доска[н]) !== цвет) continue;
    /* Бьющую фишку снимаем с доски на время поиска: она в воздухе, её
       родное поле свободно, и по правилам через него можно пролетать
       и на него можно встать [1, ст. 4.8]. Доску потом возвращаем как было. */
    const была = партия.доска[н];
    партия.доска[н] = ПУСТО;
    искатьБои(партия.доска, н, цвет, этоДамка(была), этоДамка(была), [], [имяКлетки(н)], бои, ключи);
    партия.доска[н] = была;
  }
  if (бои.length > 0) return бои;

  const тихие = [];
  for (let н = 0; н < партия.доска.length; н++) {
    if (цветФишки(партия.доска[н]) !== цвет) continue;
    for (const ход of тихиеХодыФишки(партия.доска, н, цвет, этоДамка(партия.доска[н]))) {
      тихие.push(ход);
    }
  }
  return тихие;
}

/** Все возможные ходы. Партия кончилась — ходов нет. */
function возможныеХоды(партия) {
  if (партия.завершена) return [];
  return собратьХоды(партия);
}

/**
 * Ходы одной фишки — из того же общего списка, а не по своим правилам.
 * Экрану это нужно для подсветки: он спрашивает игру, куда можно пойти,
 * и потому не может подсветить поле, которого правила не разрешают.
 */
function ходыФишки(партия, поле) {
  return возможныеХоды(партия).filter(function (ход) { return ход.откуда === поле; });
}

/** Обязан ли ходящий бить прямо сейчас. */
function естьБой(партия) {
  return возможныеХоды(партия).some(function (ход) { return ход.бой; });
}

/** Запись хода: 'e3-d4' для тихого, 'c5:e3:g5' для боя. */
function запись(ход) {
  return ход.путь.join(ход.бой ? ':' : '-');
}

/**
 * Будет ли фишка дамкой, пройдя первые «шагов» полей этого хода.
 *
 * Вопрос нужен экрану: пока человек ведёт цепочку боя по одному прыжку,
 * простая может дойти до последней горизонтали и дальше бить уже дамкой —
 * и это надо нарисовать сразу, а не в конце хода. Считать такое на экране
 * своими силами нельзя: правило превращения одно, и живёт оно здесь.
 *
 * «шагов» — сколько прыжков уже сделано: 0 значит «фишка ещё на старте».
 */
function дамкаНаШаге(партия, ход, шагов) {
  const начало = номерКлетки(ход.откуда);
  if (начало === -1) return false;
  const цвет = цветФишки(партия.доска[начало]);
  if (цвет === null) return false;
  if (этоДамка(партия.доска[начало])) return true;   // дамкой и вышла
  const сколько = Math.min(шагов, ход.путь.length - 1);
  for (let ш = 1; ш <= сколько; ш++) {
    if (последняяГоризонталь(номерКлетки(ход.путь[ш]), цвет)) return true;
  }
  return false;
}

