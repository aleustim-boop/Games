/**
 * Найти среди законных ходов тот, о котором просят.
 *
 * Просить можно двумя способами: отдать целиком ход, взятый из
 * «возможныеХоды», или назвать только откуда и куда — так удобнее
 * экрану, где человек тыкает пальцем в две клетки. Если по двум полям
 * ходов оказалось несколько (у дамки бывает: те же поля, но снимаются
 * разные фишки; у простой — та же добыча, но по одной дороге она
 * превращается в дамку, а по другой нет), придётся уточнить: назвать
 * список побитых или признак «станет дамкой». Сама игра за человека
 * выбирать не станет — молчаливый выбор за игрока и есть та ошибка,
 * которую потом ищут неделю.
 *
 * Пришедшему ходу не верим: всё, что в нём написано, кроме полей,
 * пересчитываем заново из своего списка. Иначе подделанный список
 * побитых снял бы с доски чужие фишки.
 *
 * Отдана наружу ради сервера игры вдвоём. От игрока по сети приходят
 * только два поля и список побитых, а рассказать сопернику надо весь
 * путь — иначе чужая цепочка боя выглядит на его экране телепортацией.
 * Путь уже лежит в найденном ходе, поэтому сервер зовёт эту дверь перед
 * «сделатьХод» и берёт готовое: { откуда, куда, бой, побитые, путь,
 * станетДамкой }. Второй раз искать ход у себя ему не нужно — а значит,
 * и разойтись с игрой в браузере негде.
 */
function найтиХод(партия, ход) {
  if (!ход || typeof ход !== 'object') return null;
  let годные = возможныеХоды(партия).filter(function (з) {
    return з.откуда === ход.откуда && з.куда === ход.куда;
  });
  if (Array.isArray(ход.побитые)) {
    const просят = ход.побитые.slice().sort().join(',');
    годные = годные.filter(function (з) { return з.побитые.slice().sort().join(',') === просят; });
  }
  if (typeof ход.станетДамкой === 'boolean') {
    годные = годные.filter(function (з) { return з.станетДамкой === ход.станетДамкой; });
  }
  return годные.length === 1 ? годные[0] : null;
}

/**
 * Сделать ход. Меняет партию на месте и отвечает: получилось или нет.
 * Незаконный ход не меняет ничего — это важно и экрану (тык мимо),
 * и проверкам (попытка нарушить правила должна быть отбита, а не
 * наполовину выполнена).
 */
function сделатьХод(партия, ход) {
  if (партия.завершена) return false;
  const выбранный = найтиХод(партия, ход);
  if (!выбранный) return false;

  const цвет = партия.ходит;
  const откуда = номерКлетки(выбранный.откуда);
  const куда = номерКлетки(выбранный.куда);
  const ходилаПростая = !этоДамка(партия.доска[откуда]);

  партия.доска[откуда] = ПУСТО;
  /* Побитые снимаем только теперь, когда весь ход доигран [1, ст. 4.11],
     [2] — по ходу цепочки они стояли на доске и мешали. */
  for (const поле of выбранный.побитые) партия.доска[номерКлетки(поле)] = ПУСТО;
  /* Признак дамки берём из хода, а не из последней клетки: простая могла
     стать дамкой в середине боя и потом уйти с последней горизонтали —
     дамкой она от этого быть не перестаёт. */
  партия.доска[куда] = выбранный.станетДамкой || !ходилаПростая
    ? дамкаЦвета(цвет)
    : простаяЦвета(цвет);

  обновитьСчётчикиНичьих(партия, выбранный, ходилаПростая);
  партия.ходит = соперник(цвет);
  партия.полуходов++;
  if (цвет === ЧЁРНЫЕ) партия.номерХода++;
  запомнитьПозицию(партия);
  проверитьКонец(партия);
  return true;
}

