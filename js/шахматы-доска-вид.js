/**
 * Вид доски для шахмат: пять досок на выбор.
 *
 * УСТРОЕНО КАК У ШАШЕК (см. js/шашки-доска-вид.js) — нарочно, один приём
 * на все игры: этот файл держит список и умеет применить любую доску,
 * а где хранить выбор и как показать человеку кнопки — не его дело.
 *
 * ПОЧЕМУ КЛЮЧИ ТЕ ЖЕ, ЧТО У ШАШЕК. Признак «data-доска» в проекте один
 * на две игры — так записано в js/telegram.js: «доска шашек и шахмат».
 * Значит выбранное в шашках «Холодный камень» приезжает и в шахматы.
 * Заведи мы свои имена — половина выборов не нашлась бы, и доска молча
 * откатывалась бы к умолчанию. Поэтому ключи и названия общие, а цвета
 * свои: у шахмат играют по всем 64 полям, и светлая клетка тут работает
 * куда больше, чем в шашках.
 *
 * НАРУЖУ отдаём:
 *   window.ШахматыДоска.доски()       — список { ключ, имя, образец };
 *   window.ШахматыДоска.выбрать(ключ) — применить доску;
 *   window.ШахматыДоска.какая()       — что выбрано сейчас;
 *   window.ШахматыДоска.цвета(ключ)   — краски доски, для проверок контраста.
 *
 * КАК ПРИМЕНЯЕТСЯ. Цвета кладутся переменными на сам узел доски, а рисунок
 * — классом «доска-шахмат--дерево» и подобными. Значит оформитель может
 * переопределить и то и другое, не трогая этот файл, а игра остаётся
 * живой, даже если правил для рисунка ещё нет: цвета работают сами.
 *
 * ПРО КОНТРАСТ. Числа подобраны не на глаз, а проверены мерой контраста
 * из правил доступности (отношение яркостей), порог 3,0. Проверяются три
 * вещи: клетка против клетки, фигура против клетки и подсветки против
 * обеих клеток.
 *
 * Тонкость про фигуру, которой нет в шашках. Шахматная фигура — это знак
 * с ободком: белая держится тёмным ободком, чёрная — светлым. Поэтому
 * «фигура против клетки» считается по правилу «заливка ИЛИ ободок»:
 * фигура видна, если от клетки отличается хотя бы одно из двух. Считать
 * только заливку было бы неправдой — белая фигура на светлой клетке
 * читается именно ободком, а не заливкой.
 */
(function () {
  'use strict';

  /* На сервере (Node.js) страницы нет — там от файла нужны только сами
     доски: по ним проверки считают контраст, и браузер для этого лишний. */
  const естьСтраница = typeof document !== 'undefined' && typeof window !== 'undefined';

  /* Пять досок. У каждой: две клетки, цвет подсветки выбора, кайма,
     заливка и ободок фигур. Рисунок — это класс: сам узор рисует
     оформление, а мы только называем, какой. */
  const ДОСКИ = [
    {
      ключ: 'дерево', имя: 'Тёплое дерево', рисунок: 'дерево',
      светлая: '#ead8b4', тёмная: '#96663f',
      подсветка: '#ffd66b', кайма: '#4b3221',
      белая: '#faf6ec', белаяКрай: '#3a2413',
      чёрная: '#1b1b1f', чёрнаяКрай: '#e7d9bd'
    },
    {
      ключ: 'камень', имя: 'Холодный камень', рисунок: 'камень',
      светлая: '#dde2e8', тёмная: '#6b7885',
      подсветка: '#ffe08a', кайма: '#2f3740',
      белая: '#ffffff', белаяКрай: '#232a33',
      чёрная: '#10141a', чёрнаяКрай: '#dde2e8'
    },
    {
      ключ: 'классика', имя: 'Классика', рисунок: 'гладкая',
      светлая: '#f2ead9', тёмная: '#6a6a6a',
      подсветка: '#ffd24a', кайма: '#1c1c1c',
      белая: '#fffdf7', белаяКрай: '#1c1c1c',
      чёрная: '#0d0d0d', чёрнаяКрай: '#f2ead9'
    },
    {
      ключ: 'сукно', имя: 'Зелёное сукно', рисунок: 'сукно',
      светлая: '#d6e8cb', тёмная: '#46855a',
      подсветка: '#ffe27a', кайма: '#245033',
      белая: '#fbfff7', белаяКрай: '#173322',
      чёрная: '#0f1b0d', чёрнаяКрай: '#d6e8cb'
    },
    {
      ключ: 'песок', имя: 'Песок', рисунок: 'крапинка',
      светлая: '#f6e8d2', тёмная: '#a9663c',
      подсветка: '#fff08a', кайма: '#6b3c1e',
      белая: '#fffaf0', белаяКрай: '#3d200e',
      чёрная: '#1d0f07', чёрнаяКрай: '#f6e8d2'
    }
  ];

  /* Какая доска стоит, пока человек не выбрал сам. «Тёплое дерево» —
     потому что именно так шахматы выглядели с первого дня, и у тех, кто
     уже играл, после появления выбора не изменится ничего. */
  const ПО_УМОЛЧАНИЮ = 'дерево';

  let выбранная = ПО_УМОЛЧАНИЮ;

  /** Доска по ключу или null. */
  function найти(ключ) {
    for (const доска of ДОСКИ) if (доска.ключ === ключ) return доска;
    return null;
  }

  /** Узел доски на странице. Его может ещё не быть — это не беда. */
  function узелДоски() {
    return document.getElementById('доска');
  }

  /**
   * Применить доску: цвета переменными, рисунок классом.
   *
   * Переменные ставим на сам узел доски, а не на всю страницу, нарочно:
   * образцы на экране выбора — это те же переменные на маленьких кусочках,
   * и общий корень мешал бы им показывать разные доски одновременно.
   */
  function применить(доска, куда) {
    const узел = куда || узелДоски();
    if (!узел || !доска) return;
    узел.style.setProperty('--поле-светлое', доска.светлая);
    узел.style.setProperty('--поле-тёмное', доска.тёмная);
    узел.style.setProperty('--подсветка', доска.подсветка);
    узел.style.setProperty('--рамка-доски', доска.кайма);
    узел.style.setProperty('--фигура-белая', доска.белая);
    узел.style.setProperty('--фигура-белая-край', доска.белаяКрай);
    узел.style.setProperty('--фигура-чёрная', доска.чёрная);
    узел.style.setProperty('--фигура-чёрная-край', доска.чёрнаяКрай);
    for (const другая of ДОСКИ) {
      узел.classList.toggle('доска-шахмат--' + другая.рисунок, другая.рисунок === доска.рисунок);
    }
  }

  /**
   * Кусочек доски для кнопки выбора — четыре клетки в рамке-кайме.
   *
   * Почему кусочек, а не маленькая доска целиком: на кнопке в палец
   * шириной целая доска даёт клетки по три-четыре точки, и цвет на них
   * не разобрать — именно то, ради чего человек сюда и пришёл.
   */
  function образец(доска) {
    const кусок = document.createElement('span');
    кусок.className = 'образец-доски доска-шахмат--' + доска.рисунок;
    применить(доска, кусок);
    for (let клетка = 0; клетка < 4; клетка++) {
      const поле = document.createElement('span');
      // Через одну: две светлых по краям и две тёмных — как на доске.
      поле.className = 'образец-доски__клетка образец-доски__клетка--' +
                       (клетка === 0 || клетка === 3 ? 'светлая' : 'тёмная');
      кусок.appendChild(поле);
    }
    return кусок;
  }

  /** Список досок для экрана выбора: ключ, имя и готовый образец. */
  function доски() {
    return ДОСКИ.map(function (доска) {
      return { ключ: доска.ключ, имя: доска.имя, образец: function () { return образец(доска); } };
    });
  }

  /**
   * Выбрать доску. Незнакомый ключ ничего не меняет и отвечает «нет» —
   * тогда остаётся прежняя. Где хранить выбор, файл не знает: его дело
   * — показать.
   */
  function выбрать(ключ) {
    const доска = найти(ключ);
    if (!доска) return false;
    выбранная = ключ;
    применить(доска);
    return true;
  }

  /** Какая доска выбрана сейчас. */
  function какая() {
    return выбранная;
  }

  /** Цвета доски — нужны проверкам контраста. */
  function цвета(ключ) {
    const доска = найти(ключ || выбранная);
    if (!доска) return null;
    return {
      светлая: доска.светлая, тёмная: доска.тёмная, подсветка: доска.подсветка,
      кайма: доска.кайма,
      белая: доска.белая, белаяКрай: доска.белаяКрай,
      чёрная: доска.чёрная, чёрнаяКрай: доска.чёрнаяКрай
    };
  }

  if (естьСтраница) window.ШахматыДоска = {
    доски: доски,
    выбрать: выбрать,
    какая: какая,
    цвета: цвета,
    ПО_УМОЛЧАНИЮ: ПО_УМОЛЧАНИЮ
  };

  /* Node видит те же данные — проверкам контраста браузер не нужен. */
  if (typeof module !== 'undefined' && module.exports) {
    module.exports = { ДОСКИ: ДОСКИ, ПО_УМОЛЧАНИЮ: ПО_УМОЛЧАНИЮ };
  }
})();
