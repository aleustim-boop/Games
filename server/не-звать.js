'use strict';

/* =====================================================================
   Кого не звать: память об отказах от приглашений.

   Зачем это нужно. Игрок может позвать знакомого одним нажатием — бот
   сам напишет тому в Telegram. Пока такая кнопка одна на всех, всё
   держится на одном обещании: человек, которому надоели зовы, обязан
   уметь их прекратить одним нажатием и навсегда. Без этого мы не зов
   сделали, а рассылку, и жаловаться будут на бота, а не на зовущего.

   Два разных отказа, и путать их нельзя:

     'сам'         — человек нажал в письме «Не звать меня». Это его
                     решение, и оно бессрочное: сами мы его не отменяем
                     никогда.

     'ботНеПишет'  — Telegram отказался доставить письмо (человек не
                     открывал нашего бота или закрыл ему рот). Это не
                     решение человека, а состояние дел, поэтому помним
                     сутки: нажмёт «Старт» у бота — и его снова можно
                     звать. Помним ради того, чтобы не долбиться в
                     закрытую дверь на каждое нажатие.

   Что храним. Только номер игрока в Telegram, слово-причину и время.
   Ни имён, ни кто звал, ни за какой стол — для отказа это не нужно,
   а лишнее хранение потом придётся объяснять.

   Файл переживает перезапуск сервера: «не звать меня» не то обещание,
   которое можно забыть при Ctrl+C. Пишем отложенно и через временный
   файл — перезапуск посреди записи не должен оставить обрывок.
   Устройство здесь нарочно повторяет server/знакомые.js: две памяти
   рядом, и чинить их проще одинаковыми.
   ===================================================================== */

const fs = require('fs');

/* Где лежат данные, спрашиваем у одного места на весь сервер. Своей
   копии пути здесь нет нарочно: проверки уводят папку в сторону, и
   писать мимо неё в боевые данные нельзя (см. server/папка-данных.js). */
const гдеДанные = require('./папка-данных.js');

/** Папка с данными прямо сейчас. */
function папка() { return гдеДанные.папка(); }

/** Наш файл памяти. */
function файл() { return гдеДанные.файл('не-звать.json'); }

/** Временный файл, в который пишем перед переименованием. */
function файлПокаПишем() { return файл() + '.пишем'; }

/* Слова-причины. Строками наружу их не собираем нигде, кроме этого
   словаря: опечатка в слове тихо превратила бы бессрочный отказ
   в суточный. */
const ПРИЧИНЫ = { сам: 'сам', ботНеПишет: 'ботНеПишет' };

/* Сколько помним, что бот не смог написать. Сутки: человек, решивший
   открыть бота, не должен ждать неделю, а дёргать Telegram по кругу
   каждые пять минут незачем. */
const ПОМНИМ_ЧТО_БОТ_НЕ_ПИШЕТ = 24 * 60 * 60 * 1000;

/* Записываем не сразу: отказы приходят пачками (бот молчит всем сразу),
   и бить по диску на каждый незачем. */
const ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ = 5000;

/* Потолок на весь файл — страховка от бесконечного роста. Переполнились —
   выбрасываем самые давние записи. Бессрочные отказы людей при этом
   в опасности: их мы не трогаем, пока есть что выбросить из суточных
   (см. прибраться). */
const ВСЕГО_ЗАПИСЕЙ = 20000;

/* Номер игрока → { причина, когда }. */
const запреты = new Map();

let естьЧтоЗаписать = false;
let таймерЗаписи = null;
let ужеЗагрузили = false;

/* На диск пишет только настоящий сервер — тот, что запущен напрямую
   (см. включитьЗапись в сервер.js). Проверки поднимают сервер у себя
   в процессе с этими же модулями, и их выдуманные отказы в настоящий
   файл попадать не должны. */
let записьРазрешена = false;

function включитьЗапись() {
  записьРазрешена = true;
}

/** Похоже ли это на настоящий номер игрока в Telegram. */
function этоНомерИгрока(номер) {
  return Number.isInteger(номер) && номер > 0;
}

/** Слово-причина из закрытого набора. Незнакомое считаем решением человека:
    ошибиться в сторону «не звать» безопаснее, чем в сторону «звать». */
function привестиПричину(причина) {
  return причина === ПРИЧИНЫ.ботНеПишет ? ПРИЧИНЫ.ботНеПишет : ПРИЧИНЫ.сам;
}

/** Просрочилась ли запись. Бессрочный отказ человека не просрочивается никогда. */
function записьПросрочена(запись, сейчас) {
  if (!запись || запись.причина !== ПРИЧИНЫ.ботНеПишет) return false;
  return сейчас - запись.когда > ПОМНИМ_ЧТО_БОТ_НЕ_ПИШЕТ;
}

/* ---------------------------------------------------------------------
   Чтение и запись файла
   --------------------------------------------------------------------- */

/**
 * Прочитать память с диска. Файла нет — обычное дело при первом запуске.
 * Файл испорчен — начинаем с чистого листа: ронять из-за этого сервер
 * нельзя, а потерянные отказы человек вернёт одним нажатием в письме.
 */
function загрузить() {
  ужеЗагрузили = true;
  let текст = '';
  try {
    текст = fs.readFileSync(файл(), 'utf8');
  } catch (сбой) {
    return;            // файла нет — так и должно быть при первом запуске
  }
  let прочитанное = null;
  try {
    прочитанное = JSON.parse(текст);
  } catch (сбой) {
    return;            // испорчен — молча начинаем заново
  }
  if (!прочитанное || !Array.isArray(прочитанное.запреты)) return;

  for (const запись of прочитанное.запреты) {
    if (!запись) continue;
    const номер = Number(запись.номер);
    const когда = Number(запись.когда);
    if (!этоНомерИгрока(номер) || !Number.isFinite(когда)) continue;
    запреты.set(номер, { причина: привестиПричину(запись.причина), когда: когда });
  }
  прибраться();
}

/** Сложить память в файл. Молча: беда с диском не повод ронять партии. */
function записатьСейчас() {
  естьЧтоЗаписать = false;
  const всё = { запреты: [] };
  for (const [номер, запись] of запреты) {
    всё.запреты.push({ номер: номер, причина: запись.причина, когда: запись.когда });
  }
  try {
    // Папки может не быть — например, при первом запуске на новой машине.
    fs.mkdirSync(папка(), { recursive: true });
    /* Пишем во временный файл и лишь потом переименовываем: на диске
       всегда лежит либо старая память целиком, либо новая целиком —
       но не обрывок. */
    fs.writeFileSync(файлПокаПишем(), JSON.stringify(всё), 'utf8');
    fs.renameSync(файлПокаПишем(), файл());
  } catch (сбой) {
    /* Записать не вышло — отказы останутся в памяти до следующей
       попытки. Рассказывать об этом наружу нечего. */
  }
}

/** Пометить, что память изменилась. Настоящая запись — чуть погодя. */
function записатьпогодя() {
  if (!записьРазрешена) return;
  естьЧтоЗаписать = true;
  if (таймерЗаписи !== null) return;
  таймерЗаписи = setTimeout(function () {
    таймерЗаписи = null;
    if (естьЧтоЗаписать) записатьСейчас();
  }, ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ);
  // Таймер не должен держать программу запущенной — как и у знакомых.
  if (таймерЗаписи.unref) таймерЗаписи.unref();
}

/**
 * Записать НЕМЕДЛЕННО, без пятисекундного ожидания. Зовём только для
 * отказа 'сам' — человек сам нажал «Не звать меня», и это решение
 * бессрочное: упади сервер в те пять секунд, что запись ждала диска,
 * отказ пропадёт и человека снова начнут звать письмами, хотя он явно
 * отказался (см. заголовок файла — это тот самый худший исход).
 * Отказ 'ботНеПишет' сюда не попадает нарочно: он и так суточный,
 * потеряется — бот просто попробует написать ещё раз, беды в этом нет.
 * Отменяет отложенный таймер, если он уже тикал: раз пишем прямо
 * сейчас, ждать больше нечего.
 */
function записатьСрочно() {
  if (!записьРазрешена) return;
  if (таймерЗаписи !== null) {
    clearTimeout(таймерЗаписи);
    таймерЗаписи = null;
  }
  записатьСейчас();
}

/** Записать прямо сейчас, если было что записывать (нужно при остановке). */
function дописать() {
  if (таймерЗаписи !== null) {
    clearTimeout(таймерЗаписи);
    таймерЗаписи = null;
  }
  if (естьЧтоЗаписать) записатьСейчас();
}

/* ---------------------------------------------------------------------
   Сама память
   --------------------------------------------------------------------- */

/** Выбросить просроченное и лишнее сверх потолка. */
function прибраться() {
  const сейчас = Date.now();
  for (const [номер, запись] of запреты) {
    if (записьПросрочена(запись, сейчас)) запреты.delete(номер);
  }
  if (запреты.size <= ВСЕГО_ЗАПИСЕЙ) return;

  /* Переполнение. Сначала выбрасываем суточные записи «бот не пишет» —
     они всё равно истекут сами; до бессрочных отказов людей доходим,
     только если одних суточных не хватило. */
  const порядок = Array.from(запреты.entries()).sort(function (а, б) {
    const весА = а[1].причина === ПРИЧИНЫ.ботНеПишет ? 0 : 1;
    const весБ = б[1].причина === ПРИЧИНЫ.ботНеПишет ? 0 : 1;
    if (весА !== весБ) return весА - весБ;
    return а[1].когда - б[1].когда;              // дальше — самые давние
  });
  const лишних = запреты.size - ВСЕГО_ЗАПИСЕЙ;
  for (let счёт = 0; счёт < лишних; счёт++) запреты.delete(порядок[счёт][0]);
}

/**
 * Запретить звать этого человека.
 * Причина — 'сам' (нажал «Не звать меня») или 'ботНеПишет' (Telegram
 * не доставил). Решение человека сильнее: если оно уже записано,
 * суточный отказ его не затирает и срок ему не укорачивает.
 * Возвращает правду, если запись появилась или обновилась.
 */
function запретить(номер, причина) {
  if (!ужеЗагрузили) загрузить();
  const кого = Number(номер);
  if (!этоНомерИгрока(кого)) return false;

  const слово = привестиПричину(причина);
  const прежнее = запреты.get(кого);
  if (прежнее && прежнее.причина === ПРИЧИНЫ.сам && слово === ПРИЧИНЫ.ботНеПишет) {
    return false;
  }
  запреты.set(кого, { причина: слово, когда: Date.now() });
  прибраться();
  /* 'сам' — бессрочное решение человека, его нельзя потерять при падении
     сервера посреди пятисекундного ожидания, поэтому пишем немедленно.
     'ботНеПишет' и так проживёт максимум сутки, а потеряться при падении
     ему не страшно — бот попробует написать снова, поэтому оставляем
     отложенную запись, как раньше. */
  if (слово === ПРИЧИНЫ.сам) записатьСрочно();
  else записатьпогодя();
  return true;
}

/**
 * Снова разрешить зовы (человек передумал).
 * Сегодня этим никто не пользуется: в письме есть только «Не звать меня».
 * Функция всё равно нужна — без неё отказ нечем было бы снять, и разговор
 * «верните мне зовы» упирался бы в правку файла руками.
 */
function разрешить(номер) {
  if (!ужеЗагрузили) загрузить();
  const кого = Number(номер);
  if (!этоНомерИгрока(кого)) return false;
  const было = запреты.delete(кого);
  if (было) записатьпогодя();
  return было;
}

/**
 * Почему этого человека звать нельзя: 'сам', 'ботНеПишет' или пусто,
 * если звать можно. Просроченную запись убираем прямо здесь — иначе
 * суточный отказ жил бы до ближайшей уборки.
 */
function почемуНеЗвать(номер) {
  if (!ужеЗагрузили) загрузить();
  const кого = Number(номер);
  if (!этоНомерИгрока(кого)) return '';
  const запись = запреты.get(кого);
  if (!запись) return '';
  if (записьПросрочена(запись, Date.now())) {
    запреты.delete(кого);
    записатьпогодя();
    return '';
  }
  return запись.причина;
}

/** Сколько запретов помним сейчас — для проверок. */
function сколькоЗапретов() {
  if (!ужеЗагрузили) загрузить();
  return запреты.size;
}

/** Забыть всё (нужно проверкам, чтобы начинать с чистого листа). */
function забытьВсё() {
  запреты.clear();
  ужеЗагрузили = true;
  записатьпогодя();
}

module.exports = {
  ПРИЧИНЫ: ПРИЧИНЫ,
  ПОМНИМ_ЧТО_БОТ_НЕ_ПИШЕТ: ПОМНИМ_ЧТО_БОТ_НЕ_ПИШЕТ,
  /* Путь к файлу — вопросом, а не значением: он зависит от того,
     куда уведена папка данных, и меняться может между вызовами. */
  get ФАЙЛ() { return файл(); },
  включитьЗапись: включитьЗапись,
  загрузить: загрузить,
  запретить: запретить,
  разрешить: разрешить,
  почемуНеЗвать: почемуНеЗвать,
  сколькоЗапретов: сколькоЗапретов,
  забытьВсё: забытьВсё,
  дописать: дописать
};
