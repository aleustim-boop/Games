'use strict';

/* =====================================================================
   Друзья: список, который человек собрал сам — по заявке и согласию.

   Зачем это нужно. «Знакомые» (server/знакомые.js) — это память сервера
   о том, кто с кем сидел за столом, она заводится сама и забывается
   через 60 дней. «Друзья» — другое: список, который человек составил
   осознанно, чтобы потом смотреть рейтинг «только среди своих». Раз
   список выбирают руками, у него не должно быть срока давности — иначе
   friendlist превратился бы в те же «знакомые» под другим именем.

   Устройство хранения то же, что у знакомых: ЗАПИСЬ ОДНА НА ПАРУ, ключ —
   меньший номер:больший (см. ключПары ниже). Взаимность получается
   бесплатно — «Аня видит Борю в друзьях» и «Боря видит Аню» это одна
   и та же строка. Но смысл строки другой: не время последней встречи,
   а статус заявки. Пока согласился только один — статус «ожидает»
   и известно, кто позвал. Согласились оба — «друзья».

   Отказ не «остывает»: отклонили заявку — запись просто пропадает,
   и ничто не мешает позвать снова хоть сразу же. Это тот же принцип,
   что у server/не-звать.js для чёрного списка комнат, только наоборот
   по смыслу: там отказ бессрочный, здесь бессрочно отсутствие отказа.

   Потолок на человека выше, чем у знакомых (300 против 50) — это не
   попытка навязать «социальную норму», а просто защита файла от
   бесконечного роста на людном сервере, тот же приём, другое число:
   друзей выбирают руками, и триста — щедрый запас с большим запасом.

   Файл переживает перезапуск сервера тем же способом, что и знакомые:
   пишем отложенно и через временный файл + переименование, чтобы
   перезапуск посреди записи не оставил на диске обрывок.
   ===================================================================== */

const fs = require('fs');

/* Где лежат данные, спрашиваем при каждом обращении — у общего места
   на весь сервер (см. server/папка-данных.js), а не храним свой путь:
   так проверки из tests/ не рискуют попасть в боевую папку. */
const гдеДанные = require('./папка-данных.js');

/** Папка с данными прямо сейчас. */
function папка() { return гдеДанные.папка(); }

/** Наш файл памяти. */
function файл() { return гдеДанные.файл('друзья.json'); }

/** Временный файл, в который пишем перед переименованием. */
function файлПокаПишем() { return файл() + '.пишем'; }

/* Потолок связей на человека (обе статуса — «ожидает» и «друзья» —
   считаются вместе). Технический предел, не поведенческое ограничение:
   защищает файл от неограниченного роста, а не советует, сколько
   друзей заводить. */
const СВЯЗЕЙ_НА_ЧЕЛОВЕКА = 300;

/* Записываем не сразу: несколько действий подряд (позвали, приняли)
   не повод бить по диску на каждый чих. */
const ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ = 5000;

/* Ключ пары → { первый, второй, кто_позвал, статус, когда }.
   Ключ строится из двух номеров по возрастанию (см. ключПары) — пара
   (7, 3) и пара (3, 7) это одна и та же строка, а не две. Статус —
   'ожидает' (заявка висит, кто_позвал — кто её отправил) или 'друзья'
   (оба согласны). */
const связи = new Map();

let естьЧтоЗаписать = false;
let таймерЗаписи = null;
let ужеЗагрузили = false;

/* На диск пишет только настоящий сервер — тот же приём, что у
   знакомых: проверки поднимают эти же модули у себя в процессе,
   и их выдуманные связи в боевой файл попадать не должны. */
let записьРазрешена = false;

function включитьЗапись() {
  записьРазрешена = true;
}

/** Ключ пары. Порядок номеров всегда один — в этом весь смысл. */
function ключПары(первый, второй) {
  return первый < второй ? первый + ':' + второй : второй + ':' + первый;
}

/** Похоже ли это на настоящий номер игрока в Telegram. */
function этоНомерИгрока(номер) {
  return Number.isInteger(номер) && номер > 0;
}

/* ---------------------------------------------------------------------
   Чтение и запись файла
   --------------------------------------------------------------------- */

/**
 * Прочитать память с диска. Файла нет — начинаем с чистого листа,
 * это обычное дело при первом запуске. Файл испорчен — тоже начинаем
 * заново: список друзей не та ценность, ради которой стоит ронять сервер.
 */
function загрузить() {
  ужеЗагрузили = true;
  let текст = '';
  try {
    текст = fs.readFileSync(файл(), 'utf8');
  } catch (сбой) {
    return;            // файла нет — так и должно быть при первом запуске
  }
  let прочитанное = null;
  try {
    прочитанное = JSON.parse(текст);
  } catch (сбой) {
    return;            // испорчен — молча начинаем заново
  }
  if (!прочитанное || !Array.isArray(прочитанное.связи)) return;

  for (const запись of прочитанное.связи) {
    if (!запись) continue;
    const первый = Number(запись.первый);
    const второй = Number(запись.второй);
    const ктоПозвал = Number(запись.кто_позвал);
    const когда = Number(запись.когда);
    if (!этоНомерИгрока(первый) || !этоНомерИгрока(второй)) continue;
    if (первый === второй || !Number.isFinite(когда)) continue;
    if (ктоПозвал !== первый && ктоПозвал !== второй) continue;
    if (запись.статус !== 'ожидает' && запись.статус !== 'друзья') continue;
    связи.set(ключПары(первый, второй), {
      первый: Math.min(первый, второй),
      второй: Math.max(первый, второй),
      кто_позвал: ктоПозвал,
      статус: запись.статус,
      когда: когда
    });
  }
  прибраться();
}

/** Сложить память в файл. Молча: беда с диском не повод ронять партии. */
function записатьСейчас() {
  естьЧтоЗаписать = false;
  const всё = { связи: Array.from(связи.values()) };
  try {
    // Папки может не быть — например, при первом запуске на новой машине.
    fs.mkdirSync(папка(), { recursive: true });
    /* Пишем во временный файл и лишь потом переименовываем — на диске
       всегда лежит либо старая память целиком, либо новая целиком,
       но не обрывок. Иначе перезапуск посреди записи стирал бы
       список у всех разом. */
    fs.writeFileSync(файлПокаПишем(), JSON.stringify(всё), 'utf8');
    fs.renameSync(файлПокаПишем(), файл());
  } catch (сбой) {
    /* Записать не вышло — связи останутся только в памяти
       до следующей попытки. Рассказывать об этом наружу нечего. */
  }
}

/** Пометить, что память изменилась. Настоящая запись — чуть погодя. */
function записатьпогодя() {
  if (!записьРазрешена) return;
  естьЧтоЗаписать = true;
  if (таймерЗаписи !== null) return;
  таймерЗаписи = setTimeout(function () {
    таймерЗаписи = null;
    if (естьЧтоЗаписать) записатьСейчас();
  }, ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ);
  // Таймер не должен держать программу запущенной — как и у уборщика комнат.
  if (таймерЗаписи.unref) таймерЗаписи.unref();
}

/** Записать прямо сейчас, если было что записывать (нужно при остановке). */
function дописать() {
  if (таймерЗаписи !== null) {
    clearTimeout(таймерЗаписи);
    таймерЗаписи = null;
  }
  if (естьЧтоЗаписать) записатьСейчас();
}

/* ---------------------------------------------------------------------
   Потолок на человека
   --------------------------------------------------------------------- */

/** Выбросить лишнее сверх потолка на человека — самые давние связи. */
function прибраться() {
  const сколькоУКого = new Map();
  for (const запись of связи.values()) {
    сколькоУКого.set(запись.первый, (сколькоУКого.get(запись.первый) || 0) + 1);
    сколькоУКого.set(запись.второй, (сколькоУКого.get(запись.второй) || 0) + 1);
  }
  for (const [номер, сколько] of сколькоУКого) {
    if (сколько <= СВЯЗЕЙ_НА_ЧЕЛОВЕКА) continue;
    const его = [];
    for (const [ключ, запись] of связи) {
      if (запись.первый === номер || запись.второй === номер) его.push([ключ, запись.когда]);
    }
    его.sort(function (а, б) { return а[1] - б[1]; });   // сначала самые давние
    const лишних = его.length - СВЯЗЕЙ_НА_ЧЕЛОВЕКА;
    for (let счёт = 0; счёт < лишних; счёт++) связи.delete(его[счёт][0]);
  }
}

/* ---------------------------------------------------------------------
   Действия с заявками
   --------------------------------------------------------------------- */

/**
 * Позвать в друзья. Если заявки между этими двумя ещё не было — заводит
 * новую со статусом «ожидает». Если уже была ВСТРЕЧНАЯ заявка (второй
 * уже звал первого раньше) — желания совпали, ждать нечего, сразу
 * «друзья». Повторный зов при уже висящей своей заявке или при уже
 * оформленной дружбе — просто ничего не меняет.
 *
 * Возвращает итоговый статус пары: 'ожидает' или 'друзья' — либо null,
 * если номера негодные.
 */
function позватьВДрузья(отНомера, комуНомер) {
  if (!ужеЗагрузили) загрузить();
  отНомера = Number(отНомера);
  комуНомер = Number(комуНомер);
  if (!этоНомерИгрока(отНомера) || !этоНомерИгрока(комуНомер)) return null;
  if (отНомера === комуНомер) return null;      // с собой не дружат

  const ключ = ключПары(отНомера, комуНомер);
  const запись = связи.get(ключ);

  if (запись && запись.статус === 'друзья') {
    return запись.статус;                       // уже друзья, зов ничего не меняет
  }

  if (запись && запись.статус === 'ожидает' && запись.кто_позвал === комуНомер) {
    /* Встречная заявка: второй уже звал первого раньше нас — желания
       совпали, подтверждать нечего, сразу друзья. */
    запись.статус = 'друзья';
    запись.когда = Date.now();
    прибраться();
    записатьпогодя();
    return запись.статус;
  }

  if (запись && запись.статус === 'ожидает' && запись.кто_позвал === отНомера) {
    return запись.статус;                       // уже звали, вторую заявку не заводим
  }

  связи.set(ключ, {
    первый: Math.min(отНомера, комуНомер),
    второй: Math.max(отНомера, комуНомер),
    кто_позвал: отНомера,
    статус: 'ожидает',
    когда: Date.now()
  });
  прибраться();
  записатьпогодя();
  return 'ожидает';
}

/**
 * Принять чужую заявку. Годится только на висящую заявку и только для
 * того, кому она адресована — принять собственную исходящую заявку
 * нельзя, иначе дружба завелась бы без согласия второй стороны.
 */
function принятьЗаявку(отНомера, комуНомер) {
  if (!ужеЗагрузили) загрузить();
  отНомера = Number(отНомера);
  комуНомер = Number(комуНомер);
  if (!этоНомерИгрока(отНомера) || !этоНомерИгрока(комуНомер)) return false;
  const ключ = ключПары(отНомера, комуНомер);
  const запись = связи.get(ключ);
  if (!запись || запись.статус !== 'ожидает') return false;
  if (запись.кто_позвал === отНомера) return false;   // свою же заявку не принимают
  запись.статус = 'друзья';
  запись.когда = Date.now();
  записатьпогодя();
  return true;
}

/**
 * Отклонить заявку — запись просто пропадает, без «остывания»: позвать
 * снова можно сразу же.
 */
function отклонитьЗаявку(отНомера, комуНомер) {
  if (!ужеЗагрузили) загрузить();
  отНомера = Number(отНомера);
  комуНомер = Number(комуНомер);
  if (!этоНомерИгрока(отНомера) || !этоНомерИгрока(комуНомер)) return false;
  const ключ = ключПары(отНомера, комуНомер);
  const запись = связи.get(ключ);
  if (!запись || запись.статус !== 'ожидает') return false;
  связи.delete(ключ);
  записатьпогодя();
  return true;
}

/** Убрать из друзей. Годится только на уже оформленную дружбу. */
function удалитьДруга(отНомера, комуНомер) {
  if (!ужеЗагрузили) загрузить();
  отНомера = Number(отНомера);
  комуНомер = Number(комуНомер);
  if (!этоНомерИгрока(отНомера) || !этоНомерИгрока(комуНомер)) return false;
  const ключ = ключПары(отНомера, комуНомер);
  const запись = связи.get(ключ);
  if (!запись || запись.статус !== 'друзья') return false;
  связи.delete(ключ);
  записатьпогодя();
  return true;
}

/**
 * Номера тех, с кем у этого игрока оформлена дружба. Сначала те,
 * с кем подружились позже всех.
 */
function друзьяИгрока(номер) {
  if (!ужеЗагрузили) загрузить();
  номер = Number(номер);
  if (!этоНомерИгрока(номер)) return [];
  const список = [];
  for (const запись of связи.values()) {
    if (запись.статус !== 'друзья') continue;
    if (запись.первый === номер) список.push({ номер: запись.второй, когда: запись.когда });
    else if (запись.второй === номер) список.push({ номер: запись.первый, когда: запись.когда });
  }
  список.sort(function (а, б) { return б.когда - а.когда; });
  return список.map(function (запись) { return запись.номер; });
}

/**
 * Номера тех, кто позвал этого игрока в друзья и ждёт ответа. Свои
 * же исходящие заявки сюда не попадают — это не «входящие».
 */
function входящиеЗаявки(номер) {
  if (!ужеЗагрузили) загрузить();
  номер = Number(номер);
  if (!этоНомерИгрока(номер)) return [];
  const список = [];
  for (const запись of связи.values()) {
    if (запись.статус !== 'ожидает') continue;
    if (запись.кто_позвал === номер) continue;    // это наша исходящая, не входящая
    if (запись.первый === номер || запись.второй === номер) {
      список.push({ номер: запись.кто_позвал, когда: запись.когда });
    }
  }
  список.sort(function (а, б) { return б.когда - а.когда; });
  return список.map(function (запись) { return запись.номер; });
}

/** Сколько связей помним сейчас — для проверок. */
function сколькоСвязей() {
  if (!ужеЗагрузили) загрузить();
  return связи.size;
}

/** Забыть всё (нужно проверкам, чтобы начинать с чистого листа). */
function забытьВсё() {
  связи.clear();
  ужеЗагрузили = true;
  записатьпогодя();
}

