'use strict';

/* =====================================================================
   Статистика партий: сколько играли, по дням.

   Зачем. Владелец хочет видеть, как живёт игра, — как Telegram
   показывает чужим ботам «пользователей в месяц». Людей считает бот
   (кто нажал старт, кто вернулся), а партии, столы и тех, кто сел
   играть, видит только этот сервер. Здесь они и считаются, а бот
   складывает эти числа со своими (см. дверь GET /статистика).

   Что считаем — только счётчики за день:
     комнатСоздано      сколько раз нажали «Создать игру»
     партийНачато       сколько раз розданы карты
     партийДоиграно     сколько партий дошли до конца по картам
     партийБрошено      сколько оборвались (вышли, пересобрали стол,
                        комнату убрала уборка)
     партийСБотами      партий, где за столом был хоть один бот
     партийСЛюдьми      партий, где играли одни люди
     партийПарами       партий за парным столом
     селиПоПриглашению  посадок за стол по ссылке-приглашению
     людей              сколько РАЗНЫХ людей сидело за столами

   «Людей» — единственное, что нельзя посчитать простым плюс-один: один
   человек за день садится за стол много раз, а считать его надо один.
   Поэтому за день хранится множество номеров Telegram тех, кто садился,
   а наружу уходит только его размер. Номера сюда попадают только из
   проверенной подписи (см. отметитьКтоЭто в сервер.js); кто играет не
   из Telegram, в «людей» не входит — считать его нечем.

   Ничего сверх этого не храним: ни имён, ни кодов комнат, ни карт,
   ни кто у кого выиграл. Файл лежит в server/данные — там же, где
   знакомые, и по тем же правилам: в git не едет, пишется отложенно
   и через временный файл, чтобы перезапуск не оставил обрывка.
   Хранится 60 дней, как и знакомые.
   ===================================================================== */

const fs = require('fs');
const path = require('path');

/* Где лежат данные, спрашиваем при каждом обращении — у одного
   места на весь сервер (см. server/папка-данных.js). Своей копии пути
   здесь нет нарочно: пока он был зашит тут, проверки из tests/ писали
   прямо в боевую папку и однажды стёрли настоящие данные владельца. */
const гдеДанные = require('./папка-данных.js');

/** Папка с данными прямо сейчас. */
function папка() { return гдеДанные.папка(); }

/** Наш файл памяти. */
function файл() { return гдеДанные.файл('статистика.json'); }

/** Временный файл, в который пишем перед переименованием. */
function файлПокаПишем() { return файл() + '.пишем'; }

/* Сколько дней помним. Столько же, сколько знакомых: месяц назад —
   ещё интересно, полгода назад — уже история, а не показатель. */
const ХРАНИМ_ДНЕЙ = 60;

/* Игра, которая считается в общих счётчиках. Остальные получают ещё
   и свои, с именем вида «партийНачато:шашки». Само имя берём из общего
   списка умолчаний: раньше оно было переписано в трёх файлах сервера. */
const умолчания = require('./игры/умолчания.js');
const ИГРА_ПО_УМОЛЧАНИЮ = умолчания.ПО_УМОЛЧАНИЮ;

/* Пишем не сразу: партия трогает счётчики несколько раз, и бить по диску
   на каждый чих незачем. */
const ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ = 5000;

/* Счётчики дня. Список один на весь файл: по нему и заводится пустой
   день, и читается файл с диска, и собирается сводка. Новый счётчик —
   одна строка здесь, и больше нигде. */
const СЧЁТЧИКИ = [
  'комнатСоздано',
  'партийНачато',
  'партийДоиграно',
  'партийБрошено',
  'партийСБотами',
  'партийСЛюдьми',
  'партийПарами',
  'селиПоПриглашению'
];

/* Ключ дня → { счётчики…, люди: Set<номер> }. Ключ — местная дата
   компьютера, на котором стоит сервер, в виде «2026-09-07». Владелец
   живёт там же, где сервер, поэтому «сегодня» у них совпадает. */
const дни = new Map();

let естьЧтоЗаписать = false;
let таймерЗаписи = null;
let ужеЗагрузили = false;

/* На диск пишет только настоящий сервер — тот, что запущен напрямую
   (см. включитьЗапись в сервер.js). Проверки поднимают сервер у себя
   в процессе, с этими же модулями, и без этой заслонки их партии
   попадали бы в настоящую статистику: проверено — постоянная проверка
   насоса ботов дописывала владельцу по две комнаты за прогон. */
let записьРазрешена = false;

function включитьЗапись() {
  записьРазрешена = true;
}

/** «2026-09-07» по местному времени. */
function ключДня(время) {
  const дата = new Date(время === undefined ? Date.now() : время);
  const месяц = String(дата.getMonth() + 1).padStart(2, '0');
  const число = String(дата.getDate()).padStart(2, '0');
  return дата.getFullYear() + '-' + месяц + '-' + число;
}

/** Ключ дня, отстоящего от сегодняшнего на столько-то дней назад. */
function ключДняНазад(сколькоНазад) {
  const дата = new Date();
  дата.setDate(дата.getDate() - сколькоНазад);
  return ключДня(дата.getTime());
}

/** Пустой день: все счётчики по нулям, людей нет. */
function пустойДень() {
  const день = { люди: new Set() };
  for (const имя of СЧЁТЧИКИ) день[имя] = 0;
  return день;
}

/** Похоже ли это на настоящий номер игрока в Telegram. */
function этоНомерИгрока(номер) {
  return Number.isInteger(номер) && номер > 0;
}

/* ---------------------------------------------------------------------
   Чтение и запись файла
   --------------------------------------------------------------------- */

/**
 * Прочитать память с диска. Файла нет или он испорчен — начинаем
 * с чистого листа: статистика не та ценность, ради которой стоит
 * ронять сервер с партиями.
 */
function загрузить() {
  ужеЗагрузили = true;
  let текст = '';
  try {
    текст = fs.readFileSync(файл(), 'utf8');
  } catch (сбой) {
    return;            // файла нет — так и должно быть при первом запуске
  }
  let прочитанное = null;
  try {
    прочитанное = JSON.parse(текст);
  } catch (сбой) {
    return;            // испорчен — молча начинаем заново
  }
  if (!прочитанное || !Array.isArray(прочитанное.дни)) return;

  for (const запись of прочитанное.дни) {
    if (!запись || typeof запись.день !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(запись.день)) continue;
    const день = пустойДень();
    for (const имя of Object.keys(запись)) {
      if (имя === 'день' || имя === 'люди') continue;
      // Имена счётчиков закрытые: общие из списка и «общий:игра» для игр.
      const общий = имя.split(':')[0];
      if (СЧЁТЧИКИ.indexOf(общий) === -1) continue;
      const число = Number(запись[имя]);
      день[имя] = Number.isInteger(число) && число > 0 ? число : 0;
    }
    for (const номер of (Array.isArray(запись.люди) ? запись.люди : [])) {
      const целое = Number(номер);
      if (этоНомерИгрока(целое)) день.люди.add(целое);
    }
    дни.set(запись.день, день);
  }
  прибраться();
}

/** Сложить память в файл. Молча: беда с диском не повод ронять партии. */
function записатьСейчас() {
  естьЧтоЗаписать = false;
  const список = [];
  for (const [ключ, день] of дни) {
    const запись = { день: ключ };
    for (const имя of счётчикиДня(день)) запись[имя] = день[имя];
    запись.люди = Array.from(день.люди);
    список.push(запись);
  }
  try {
    fs.mkdirSync(папка(), { recursive: true });
    /* Во временный файл и переименование: на диске всегда лежит либо
       старая память целиком, либо новая целиком — обрывка не бывает. */
    fs.writeFileSync(файлПокаПишем(), JSON.stringify({ дни: список }), 'utf8');
    fs.renameSync(файлПокаПишем(), файл());
  } catch (сбой) {
    /* Не записалось — числа останутся в памяти до следующей попытки. */
  }
}

/** Пометить, что память изменилась. Настоящая запись — чуть погодя. */
function записатьПогодя() {
  if (!записьРазрешена) return;
  естьЧтоЗаписать = true;
  if (таймерЗаписи !== null) return;
  таймерЗаписи = setTimeout(function () {
    таймерЗаписи = null;
    if (естьЧтоЗаписать) записатьСейчас();
  }, ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ);
  // Таймер не должен держать программу запущенной — как и у уборщика.
  if (таймерЗаписи.unref) таймерЗаписи.unref();
}

/** Записать прямо сейчас, если было что (нужно при остановке сервера). */
function дописать() {
  if (таймерЗаписи !== null) {
    clearTimeout(таймерЗаписи);
    таймерЗаписи = null;
  }
  if (естьЧтоЗаписать) записатьСейчас();
}

/* ---------------------------------------------------------------------
   Сам счёт
   --------------------------------------------------------------------- */

/** Выбросить дни старше срока хранения. */
function прибраться() {
  const самыйСтарый = ключДняНазад(ХРАНИМ_ДНЕЙ - 1);
  for (const ключ of дни.keys()) {
    // Ключи вида «2026-09-07» сравниваются как строки правильно.
    if (ключ < самыйСтарый) дни.delete(ключ);
  }
}

/** Сегодняшний день — завести, если ещё не заводили. */
function сегодня() {
  if (!ужеЗагрузили) загрузить();
  const ключ = ключДня();
  let день = дни.get(ключ);
  if (!день) {
    день = пустойДень();
    дни.set(ключ, день);
    прибраться();
  }
  return день;
}

/**
 * Плюс один к счётчику за сегодня. Незнакомое имя счётчика — ошибка
 * в коде сервера, а не в данных; о ней говорим в консоль и не падаем.
 */
function учесть(что, игра) {
  if (СЧЁТЧИКИ.indexOf(что) === -1) {
    console.warn('Статистика: незнакомый счётчик «' + что + '»');
    return;
  }
  const день = сегодня();
  день[что]++;
  /* Вторая игра считается ещё и отдельно — счётчиком «что:шашки».
     Общие счётчики при этом остаются общими, и вот почему: их читает
     бот и показывает владельцу сводку за месяцы. Перенеси мы дурака
     в «партийНачато:дурак» — сводка скачком потеряла бы всю историю,
     и человек прочитал бы это как поломку. Поэтому только добавляем. */
  if (игра && игра !== ИГРА_ПО_УМОЛЧАНИЮ) {
    const ключ = что + ':' + игра;
    день[ключ] = (день[ключ] || 0) + 1;
  }
  записатьПогодя();
}

/** Все счётчики этого дня по именам: и общие, и разбитые по играм. */
function счётчикиДня(день) {
  return Object.keys(день).filter(function (имя) {
    return имя !== 'люди' && typeof день[имя] === 'number';
  });
}

/**
 * Человек сел за стол. Считаем только тех, у кого есть номер из подписи
 * Telegram; второй раз за день тот же номер ничего не меняет.
 */
function учестьЧеловека(номер) {
  if (!этоНомерИгрока(номер)) return;
  const день = сегодня();
  if (день.люди.has(номер)) return;
  день.люди.add(номер);
  записатьПогодя();
}

/**
 * Сводка за последние столько-то дней, включая сегодняшний.
 * Счётчики складываются, а люди объединяются: один и тот же человек
 * в семи днях — это один человек, а не семь.
 */
function сводка(сколькоДней) {
  if (!ужеЗагрузили) загрузить();
  const итог = {};
  for (const имя of СЧЁТЧИКИ) итог[имя] = 0;
  const люди = new Set();
  const самыйСтарый = ключДняНазад(сколькоДней - 1);
  for (const [ключ, день] of дни) {
    if (ключ < самыйСтарый) continue;
    for (const имя of счётчикиДня(день)) {
      итог[имя] = (итог[имя] || 0) + день[имя];
    }
    for (const номер of день.люди) люди.add(номер);
  }
  итог.людей = люди.size;
  return итог;
}

/**
 * Готовый ответ для бота: за сегодня, за неделю и за месяц.
 * Собирается поле за полем из чисел; номеров людей здесь нет и быть
 * не может — только сколько их.
 */
function отчёт() {
  return {
    день: ключДня(),
    хранимДней: ХРАНИМ_ДНЕЙ,
    сегодня: сводка(1),
    дней7: сводка(7),
    дней30: сводка(30)
  };
}

/** Забыть всё (нужно проверкам, чтобы начинать с чистого листа). */
function забытьВсё() {
  дни.clear();
  ужеЗагрузили = true;
  записатьПогодя();
}

module.exports = {
  ХРАНИМ_ДНЕЙ: ХРАНИМ_ДНЕЙ,
  СЧЁТЧИКИ: СЧЁТЧИКИ,
  /* Путь к файлу — вопросом, а не значением: он зависит от того,
     куда уведена папка данных, и меняться может между вызовами. */
  get ФАЙЛ() { return файл(); },
  ключДня: ключДня,
  включитьЗапись: включитьЗапись,
  загрузить: загрузить,
  учесть: учесть,
  учестьЧеловека: учестьЧеловека,
  сводка: сводка,
  отчёт: отчёт,
  забытьВсё: забытьВсё,
  дописать: дописать
};
