/* =====================================================================
   УЧЁТ «КТО КОГО ПРИВЁЛ» (план: штаб/план-позвать-друга.md, этап Э1).

   Зачем. Владелец хочет «Позвать друга» с наградой: когда друг сыграл
   первую партию, пригласивший получает награду. Этот модуль — только
   память и правила засчитывания. Он ЧИСТЫЙ: комнат, рейтинга и сети
   не знает. Подключает его к серверу этап Э4, а внешнее (играл ли друг
   раньше, часы) приходит через подключить() — как в итог-в-бот.js.

   Как это работает:
     1. У каждого пригласившего — постоянный случайный код (8 знаков);
        номер Telegram в ссылку не идёт.
     2. отметитьПриход — привязка друга к пригласившему. Привязка одна
        на друга навсегда: первая побеждает, перепривязки нет.
     3. партияСыграна — друг сыграл учтённую партию. Если привязка свежая
        и партия подходит по виду, друг засчитан (один раз навсегда),
        а пригласившему и самому другу открываются награды.

   Номера Telegram лежат только в файле привёл-друга.json (папка данных,
   в git не едет). Наружу, в сводку, — только числа.
   ===================================================================== */

const fs = require('fs');
const крипто = require('crypto');
const гдеДанные = require('./папка-данных.js');

/* ---------------------------------------------------------------------
   ТАБЛИЦА РЕШЕНИЙ. Решений владельца пока нет — здесь рекомендованные
   (план, раздел 5). Поменять решение = поправить эту таблицу, не код.
   --------------------------------------------------------------------- */

/** В1. Награды пригласившему: на скольки друзьях что открывается. */
const СТУПЕНИ = [
  { друзей: 1, награды: ['значок-друг-1'] },
  { друзей: 3, награды: ['рубашка-друг', 'значок-друг-3'] },
  { друзей: 5, награды: ['значок-друг-5'] }
];

/** В2. Награды самому другу после его первой засчитанной партии ([] — не даём). */
const НАГРАДЫ_ДРУГУ = ['рубашка-друг'];

/** В3. Какие партии засчитываются. 'стол' — вёл сервер; 'билет' — партия
 *  с ботом, исход принёс браузер, подделать скриптом можно — не берём. */
const ЗАСЧИТЫВАЕМЫЕ_ВИДЫ = ['стол'];

/** Привязка живёт столько дней: не сыграл за это время — не засчитывается. */
const СРОК_ПРИВЯЗКИ_ДНЕЙ = 30;

/** Не больше стольких засчитанных друзей пригласившему за сутки (против ферм). */
const ДРУЗЕЙ_В_СУТКИ = 10;

/* ---------------------------------------------------------------------
   Технические пределы и мелочи.
   --------------------------------------------------------------------- */

const СУТКИ = 24 * 60 * 60 * 1000;
const ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ = 5000;
const ПРИВЯЗОК_ВСЕГО = 100000;               // сверх — выбрасываем только просроченные незасчитанные
const ДЛИНА_КОДА = 8;
const АЗБУКА = 'abcdefghijklmnopqrstuvwxyz0123456789';
const ГОДНЫЙ_КОД = /^[a-z0-9]{8}$/;
const БАЗА_ЛИЧИН = 900000000000000;           // 9·10^14: заведомо не номер Telegram
const ОТКУДА_БЫВАЕТ = ['бот', 'стол'];       // закрытый список источников привязки

function файл() { return гдеДанные.файл('привёл-друга.json'); }
function файлПокаПишем() { return файл() + '.пишем'; }
function файлБитый() { return файл() + '.битый'; }

/* ---------------------------------------------------------------------
   Подключение внешнего мира.
   --------------------------------------------------------------------- */

let игралРаньшеВнешний = null;
let этоЛичинаВнешний = null;
let сейчасФункция = Date.now;
let потолокПривязок = 100000;

/**
 * Подключить модуль к настоящему миру.
 *   игралРаньше(номер) — true, если у человека уже была учтённая партия
 *                         (Э4: рейтинг.моиОчкиПоИграм(номер).length > 0).
 *                         Не подключено или упало — привязки нет, отказ «нет-проверки».
 *   потолокПривязок    — сколько привязок держим (для проверок; обычно 100 000).
 *   этоЛичина(номер)   — личина-бот (server/личины.js); сверх номера ≥ 9·10^14.
 *   сейчас()           — подменяемые часы для проверок.
 */
function подключить(зависимости) {
  зависимости = зависимости || {};
  игралРаньшеВнешний = typeof зависимости.игралРаньше === 'function' ? зависимости.игралРаньше : null;
  этоЛичинаВнешний = typeof зависимости.этоЛичина === 'function' ? зависимости.этоЛичина : null;
  сейчасФункция = typeof зависимости.сейчас === 'function' ? зависимости.сейчас : Date.now;
  потолокПривязок = Number.isInteger(зависимости.потолокПривязок) && зависимости.потолокПривязок > 0
    ? зависимости.потолокПривязок : ПРИВЯЗОК_ВСЕГО;
}

/** Сбой внешней функции не должен ронять партию: считаем ответ «нет». */
function безопасно(функция, номер) {
  if (!функция) return false;
  try { return Boolean(функция(номер)); } catch (беда) { return false; }
}

/**
 * Играл ли человек раньше: true / false, а если проверить нечем (функция не
 * подключена или упала) — null. Вслепую «не играл» не считаем: иначе старый
 * игрок прошёл бы как новичок и принёс пригласившему награду.
 */
function игралРаньше(номер) {
  if (!игралРаньшеВнешний) return null;
  try { return Boolean(игралРаньшеВнешний(номер)); } catch (беда) { return null; }
}

function этоНомерИгрока(номер) {
  return Number.isInteger(номер) && номер > 0;
}

function этоЛичина(номер) {
  return номер >= БАЗА_ЛИЧИН || безопасно(этоЛичинаВнешний, номер);
}

/* ---------------------------------------------------------------------
   Память: коды и привязки.
   --------------------------------------------------------------------- */

/** номер пригласившего → его код */
const кодыПоНомеру = new Map();
/** код → номер пригласившего */
const номераПоКоду = new Map();
/** номер друга → { кто, откуда, игра, когда, засчитан (время или 0) } */
const привязки = new Map();

let ужеЗагрузили = false;
let записьРазрешена = false;
let естьЧтоЗаписать = false;
let таймерЗаписи = null;

/** На диск пишет только настоящий сервер (как у приглашений). */
function включитьЗапись() {
  записьРазрешена = true;
  if (естьЧтоЗаписать) записатьПогодя();
}

/** Привязка с диска — поле за полем; негодная — null. */
function чистаяПривязка(сырая) {
  if (!сырая || typeof сырая !== 'object') return null;
  const кто = Number(сырая.кто);
  const когда = Number(сырая.когда);
  if (!этоНомерИгрока(кто) || !Number.isFinite(когда) || когда <= 0) return null;
  const засчитан = Number(сырая.засчитан);
  return {
    кто: кто,
    откуда: ОТКУДА_БЫВАЕТ.indexOf(сырая.откуда) !== -1 ? сырая.откуда : 'бот',
    игра: typeof сырая.игра === 'string' ? сырая.игра.slice(0, 40) : '',
    когда: когда,
    засчитан: Number.isFinite(засчитан) && засчитан > 0 ? засчитан : 0
  };
}

/** Файл битый — откладываем в сторону, чтобы не затереть первой записью. */
function отложитьБитый() {
  try {
    fs.renameSync(файл(), файлБитый());
  } catch (сбой) {
    /* Не вышло — начнём с чистого листа: учёт не роняет сервер. */
  }
}

function загрузить() {
  if (ужеЗагрузили) return;
  ужеЗагрузили = true;
  let прочитанное = null;
  try {
    прочитанное = JSON.parse(fs.readFileSync(файл(), 'utf8'));
  } catch (сбой) {
    прочитанное = null;
    if (сбой && сбой.code !== 'ENOENT') отложитьБитый();
  }
  if (!прочитанное || typeof прочитанное !== 'object') return;
  const коды = прочитанное.коды && typeof прочитанное.коды === 'object' ? прочитанное.коды : {};
  for (const ключ of Object.keys(коды)) {
    const номер = Number(ключ);
    const код = коды[ключ];
    if (!этоНомерИгрока(номер) || typeof код !== 'string' || !ГОДНЫЙ_КОД.test(код)) continue;
    if (номераПоКоду.has(код)) continue;
    кодыПоНомеру.set(номер, код);
    номераПоКоду.set(код, номер);
  }
  const сохранённые = прочитанное.привязки && typeof прочитанное.привязки === 'object' ? прочитанное.привязки : {};
  for (const ключ of Object.keys(сохранённые)) {
    const друг = Number(ключ);
    const привязка = чистаяПривязка(сохранённые[ключ]);
    if (этоНомерИгрока(друг) && привязка) привязки.set(друг, привязка);
  }
}

function записатьСейчас() {
  const коды = {};
  for (const [номер, код] of кодыПоНомеру) коды[номер] = код;
  const всеПривязки = {};
  for (const [друг, привязка] of привязки) всеПривязки[друг] = привязка;
  try {
    fs.mkdirSync(гдеДанные.папка(), { recursive: true });
    fs.writeFileSync(файлПокаПишем(), JSON.stringify({ коды: коды, привязки: всеПривязки }), 'utf8');
    fs.renameSync(файлПокаПишем(), файл());
    /* Флаг снимаем, только когда файл правда на месте: сбой диска не теряет правки. */
    естьЧтоЗаписать = false;
  } catch (сбой) {
    /* Не записалось — флаг остаётся, следующая запись попробует снова. */
  }
}

function записатьПогодя() {
  естьЧтоЗаписать = true;
  if (!записьРазрешена || таймерЗаписи !== null) return;
  таймерЗаписи = setTimeout(function () {
    таймерЗаписи = null;
    if (естьЧтоЗаписать) записатьСейчас();
  }, ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ);
  if (таймерЗаписи.unref) таймерЗаписи.unref();
}

/**
 * Записать немедленно. Для нового кода пригласившего: ссылка с ним уходит
 * сразу, и если сервер упадёт в ближайшие 5 секунд, код пропал бы, а ссылка
 * осталась бы у друзей «в никуда».
 */
function записатьСразу() {
  естьЧтоЗаписать = true;
  if (!записьРазрешена) return;
  записатьСейчас();
}

/** Записать прямо сейчас, если было что (остановка сервера, проверки). */
function дописать() {
  if (таймерЗаписи !== null) {
    clearTimeout(таймерЗаписи);
    таймерЗаписи = null;
  }
  if (записьРазрешена && естьЧтоЗаписать) записатьСейчас();
}

/* ---------------------------------------------------------------------
   Коды пригласивших.
   --------------------------------------------------------------------- */

function новыйКод() {
  for (;;) {
    const байты = крипто.randomBytes(ДЛИНА_КОДА);
    let код = '';
    for (let и = 0; и < ДЛИНА_КОДА; и++) код += АЗБУКА[байты[и] % АЗБУКА.length];
    if (!номераПоКоду.has(код)) return код;
  }
}

/** Постоянный код пригласившего (выдаётся при первом обращении) или '' для негодного номера. */
function кодПригласившего(номер) {
  загрузить();
  if (!этоНомерИгрока(номер) || этоЛичина(номер)) return '';
  let код = кодыПоНомеру.get(номер);
  if (!код) {
    код = новыйКод();
    кодыПоНомеру.set(номер, код);
    номераПоКоду.set(код, номер);
    записатьСразу();                                                            // проверка:код-сразу
  }
  return код;
}

/** Номер пригласившего по коду или null. Только для сервера: наружу не отдавать. */
function ктоПоКоду(код) {
  загрузить();
  if (typeof код !== 'string' || !ГОДНЫЙ_КОД.test(код)) return null;
  const номер = номераПоКоду.get(код);
  return номер === undefined ? null : номер;
}

/* ---------------------------------------------------------------------
   Привязка друга.
   --------------------------------------------------------------------- */

function отказ(почему) {
  return { ок: false, почему: почему };
}

/**
 * Сверх потолка выбрасываем только незасчитанные и уже просроченные привязки
 * (они всё равно не засчитались бы). Засчитанные не трогаем никогда: иначе у
 * пригласившего пропали бы друзья и награды, а друга можно было бы привязать
 * заново. Если выбрасывать нечего — потолок временно превышен: это дешевле.
 */
function прибратьсяСверхПотолка() {
  if (привязки.size <= потолокПривязок) return;
  const сейчас = сейчасФункция();
  for (const [друг, привязка] of привязки) {
    if (привязки.size <= потолокПривязок) break;
    if (привязка.засчитан) continue;                                            // проверка:засчитанные-целы
    if (сейчас - привязка.когда > СРОК_ПРИВЯЗКИ_ДНЕЙ * СУТКИ) привязки.delete(друг);
  }
}

/**
 * Привязать друга к пригласившему. Все номера — из ПРОВЕРЕННЫХ источников
 * (подпись Telegram или сервер за столом). откуда: 'бот' | 'стол'.
 * Ответ: { ок: true } или { ок: false, почему } — 'номер' | 'откуда' | 'сам' |
 * 'личина' | 'уже' | 'играл' | 'нет-проверки' (играл ли друг — проверить нечем:
 * функция игралРаньше не подключена или упала; привязку не даём).
 */
function отметитьПриход(друг, кто, откуда, игра) {
  загрузить();
  if (!этоНомерИгрока(друг) || !этоНомерИгрока(кто)) return отказ('номер');
  if (ОТКУДА_БЫВАЕТ.indexOf(откуда) === -1) return отказ('откуда');
  if (друг === кто) return отказ('сам');                                       // проверка:сам
  if (этоЛичина(друг) || этоЛичина(кто)) return отказ('личина');
  if (привязки.has(друг)) return отказ('уже');
  const играл = игралРаньше(друг);
  if (играл === null) return отказ('нет-проверки');                            // проверка:нет-проверки
  if (играл) return отказ('играл');                                            // проверка:играл
  привязки.set(друг, {
    кто: кто,
    откуда: откуда,
    игра: typeof игра === 'string' ? игра.slice(0, 40) : '',
    когда: сейчасФункция(),
    засчитан: 0
  });
  прибратьсяСверхПотолка();
  записатьПогодя();
  return { ок: true };
}

/* ---------------------------------------------------------------------
   Засчитывание и награды.
   --------------------------------------------------------------------- */

/** Сколько друзей пригласившего уже засчитано. */
function сколькоДрузей(кто) {
  let число = 0;
  for (const привязка of привязки.values()) {
    if (привязка.кто === кто && привязка.засчитан) число++;
  }
  return число;
}

/** Сколько друзей пригласившего засчитано за последние сутки. */
function засчитаноЗаСутки(кто) {
  const от = сейчасФункция() - СУТКИ;
  let число = 0;
  for (const привязка of привязки.values()) {
    if (привязка.кто === кто && привязка.засчитан >= от) число++;
  }
  return число;
}

/** Награды пригласившего при таком числе друзей. */
function наградыЗаДрузей(друзей) {
  const список = [];
  for (const ступень of СТУПЕНИ) {
    if (друзей >= ступень.друзей) ступень.награды.forEach(function (н) { if (список.indexOf(н) === -1) список.push(н); });
  }
  return список;
}

/**
 * Друг сыграл учтённую партию. партия: { игра, вид: 'стол'|'билет', когда }
 * (когда — время окончания партии, мс; нет — «сейчас»).
 * Ответ: { ок: false, почему } — 'вид' | 'нет' | 'уже' | 'раньше' | 'срок' | 'предел';
 *   или { ок: true, пригласивший, друзей, новыеНаграды, наградыДругу } — это для
 *   письма и записи в Э4, не для показа наружу.
 */
function партияСыграна(номер, партия) {
  загрузить();
  const данные = партия || {};
  if (ЗАСЧИТЫВАЕМЫЕ_ВИДЫ.indexOf(данные.вид) === -1) return отказ('вид');
  const привязка = привязки.get(номер);
  if (!привязка) return отказ('нет');
  if (привязка.засчитан) return отказ('уже');
  const сейчас = сейчасФункция();
  const когда = Number.isFinite(Number(данные.когда)) && Number(данные.когда) > 0 ? Number(данные.когда) : сейчас;
  if (когда < привязка.когда) return отказ('раньше');
  if (сейчас - привязка.когда > СРОК_ПРИВЯЗКИ_ДНЕЙ * СУТКИ) return отказ('срок');
  if (засчитаноЗаСутки(привязка.кто) >= ДРУЗЕЙ_В_СУТКИ) return отказ('предел');
  const былоНаград = наградыЗаДрузей(сколькоДрузей(привязка.кто));
  привязка.засчитан = сейчас;                                                   // проверка:засчитан
  записатьПогодя();
  const друзей = сколькоДрузей(привязка.кто);
  const новые = наградыЗаДрузей(друзей).filter(function (н) { return былоНаград.indexOf(н) === -1; });
  return {
    ок: true,
    пригласивший: привязка.кто,
    друзей: друзей,
    новыеНаграды: новые,
    наградыДругу: НАГРАДЫ_ДРУГУ.slice()
  };
}

/**
 * Награды человека как пригласившего и как друга.
 * { друзей, награды[], следующая: { друзей, осталось, награды[] } | null }
 */
function моиНаграды(номер) {
  загрузить();
  const друзей = этоНомерИгрока(номер) ? сколькоДрузей(номер) : 0;
  const награды = наградыЗаДрузей(друзей);
  const сам = привязки.get(номер);
  if (сам && сам.засчитан) {
    НАГРАДЫ_ДРУГУ.forEach(function (н) { if (награды.indexOf(н) === -1) награды.push(н); });
  }
  const дальше = СТУПЕНИ.filter(function (с) { return с.друзей > друзей; })[0];
  return {
    друзей: друзей,
    награды: награды,
    следующая: дальше ? { друзей: дальше.друзей, осталось: дальше.друзей - друзей, награды: дальше.награды.slice() } : null
  };
}

/**
 * Сводка за последние «дней» дней (не число или ≤ 0 — за всё). ТОЛЬКО числа:
 * ни номеров Telegram, ни кодов — её можно показывать наружу.
 *   привязок — друзей приведено; засчитано — из них сыграли; ждут — ещё нет;
 *   пригласивших — сколько разных людей привели хоть одного.
 */
function сводка(дней) {
  загрузить();
  const окно = Number(дней) > 0 ? Number(дней) * СУТКИ : Infinity;
  const от = сейчасФункция() - окно;
  const итог = { привязок: 0, засчитано: 0, ждут: 0, пригласивших: 0 };
  const разные = new Set();
  for (const привязка of привязки.values()) {
    if (привязка.когда < от) continue;
    итог.привязок++;
    if (привязка.засчитан) итог.засчитано++; else итог.ждут++;
    разные.add(привязка.кто);
  }
  итог.пригласивших = разные.size;
  return итог;
}

