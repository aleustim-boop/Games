/** Таблица результатов игры/режима; заводим по первому обращению. */
function таблицаРезультатов(игра, режим) {
  if (!результаты.has(игра)) результаты.set(игра, new Map());
  const поИграм = результаты.get(игра);
  if (!поИграм.has(режим)) поИграм.set(режим, new Map());
  return поИграм.get(режим);
}

/** Прочитать файл. Нет файла или он испорчен — начинаем с чистого листа. */
function загрузить() {
  ужеЗагрузили = true;
  let прочитанное = null;
  try {
    прочитанное = JSON.parse(fs.readFileSync(файл(), 'utf8'));
  } catch (сбой) {
    return; // файла нет или он испорчен — это не беда, начинаем с нуля
  }
  if (!прочитанное || !Array.isArray(прочитанное.результаты)) return;
  for (const запись of прочитанное.результаты) {
    if (!запись || !этоНомерИгрока(запись.номер)) continue;
    if (typeof запись.игра !== 'string' || !запись.игра) continue;
    if (typeof запись.режим !== 'string' || !запись.режим) continue;
    if (typeof запись.значение !== 'number' || !Number.isFinite(запись.значение)) continue;
    таблицаРезультатов(запись.игра, запись.режим).set(запись.номер, {
      номер: запись.номер,
      имя: typeof запись.имя === 'string' ? запись.имя : '',
      значение: запись.значение,
      дата: typeof запись.дата === 'string' ? запись.дата : '',
      неделя: запись.неделя && /^\d{4}-\d{2}-\d{2}$/.test(запись.неделя.с) && Number.isFinite(запись.неделя.значение)
        ? { с: запись.неделя.с, значение: запись.неделя.значение } : null
    });
  }
}

/** Сложить память в файл: временный файл + переименование, без обрывков. */
function записатьСейчас() {
  естьЧтоЗаписать = false;
  const список = [];
  for (const [игра, поРежимам] of результаты) {
    for (const [режим, таблица] of поРежимам) {
      for (const запись of таблица.values()) {
        список.push({
          игра: игра,
          режим: режим,
          номер: запись.номер,
          имя: запись.имя,
          значение: запись.значение,
          дата: запись.дата,
          неделя: запись.неделя || null
        });
      }
    }
  }
  try {
    fs.mkdirSync(папка(), { recursive: true });
    fs.writeFileSync(файлПокаПишем(), JSON.stringify({ результаты: список }), 'utf8');
    fs.renameSync(файлПокаПишем(), файл());
  } catch (сбой) {
    /* Не записалось — память останется до следующей попытки. Ронять
       партию из-за диска нельзя, так же как в server/рейтинг.js. */
  }
}

/** Записать НЕМЕДЛЕННО — здесь так пишется всегда, см. шапку файла. */
function записатьСрочно() {
  if (!записьРазрешена) return;
  естьЧтоЗаписать = true;
  записатьСейчас();
}

/** Записать прямо сейчас, если есть что (нужно при остановке сервера). */
function дописать() {
  if (естьЧтоЗаписать) записатьСейчас();
}

function загрузитьЕслиНужно() {
  if (!ужеЗагрузили) загрузить();
}

