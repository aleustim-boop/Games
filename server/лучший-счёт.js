/* =====================================================================
   ЛУЧШИЙ СЧЁТ: рейтинг одиночных игр-головоломок по лучшему результату.

   Зачем свой файл, а не общий server/рейтинг.js. У 2048, судоку, блоков,
   три в ряд и змейки нет партии с соперником — рейтинг там не «очки за
   встречу», а «место по лучшему результату» (решение владельца, план
   штаб/план-рейтинг-бот-и-счёт.md, «Ответы владельца 26.09»: «рейтинг-2048
   — место по лучшему счёту в партии»). Смешивать это с очками рейтинга
   нельзя: у 2048 счёт — тысячи и миллионы, он задавил бы «Все игры» и
   профиль игрока (решение штаба, план, раздел 2, пункт 6). Игры со
   счётом в сумму «Все игры» не входят вовсе — у них отдельная таблица
   на каждую игру и каждый режим.

   ЧЕСТНО О ПРЕДЕЛАХ ЗАЩИТЫ (план, раздел «Честно о пределах»). Партия
   идёт целиком в браузере, и число счёта — это слово браузера. Сервер
   может проверить:
     • кто прислал (подпись Telegram — номер приходит сюда уже проверенным);
     • что билет взят ДО партии и режим записан в нём;
     • сколько прошло по часам СЕРВЕРА между выдачей билета и сдачей;
     • что счёт — целое неотрицательное число в пределах потолка режима
       (js/игры-реестр.js, поле счёт.потолок — откуда взяты числа, см. там);
     • что скорость набора очков правдоподобна (не быстрее счёт.заСекунду);
     • что заявленное время решения не меньше разумного минимума режима
       (счёт.неБыстрее) и не больше времени, прошедшего по часам сервера;
     • частоту сдач (не чаще раза в СДАЧА_НЕ_ЧАЩЕ, не больше СДАЧ_В_СУТКИ
       в сутки) — тот же приём, что у билетов партии с ботом (билеты.js).
   Сервер НЕ может отличить честный счёт от правдоподобной выдумки и не
   может отличить человека от программы-решателя. Настоящая защита —
   повтор партии на сервере по журналу ходов и «зерну» — вынесена в
   этап Э4.9 (журнала ходов в играх пока нет). Билет уже несёт зерно
   (случайное число) на будущее: сейчас оно лежит рядом и никак не
   проверяется, но переделывать билет тогда не придётся.

   ЧТО ХРАНИМ. На каждую пару (игра, режим) — по одному лучшему результату
   на игрока: номер Telegram, имя, значение (очки или секунды), дата
   улучшения. Для публичной таблицы дополнительно хранится лучший
   принятый результат текущей недели, даже если общий рекорд выше.
   Журнал всех прошлых попыток не хранится.

   НАРУЖУ НОМЕР НЕ УХОДИТ НИКОГДА — тот же принцип, что в server/рейтинг.js
   (см. там же, «НАРУЖУ НОМЕР НЕ УХОДИТ НИКОГДА»). Строка среза собирается
   вручную, поле за полем (см. функцию строкаНаружу).

   ЗАПИСЬ НА ДИСК — немедленная (записьСрочно, без пятисекундного
   ожидания, как в server/рейтинг.js). Отложенной записи здесь нарочно
   нет: партия-головоломка идёт редко, в отличие от партий с людьми, и
   потерять только что поставленный рекорд при падении сервера — обиднее,
   чем лишний раз тронуть диск.

   ПУТЬ К ФАЙЛУ памяти спрашивается у общего server/папка-данных.js
   (см. пояснение там же: путь можно увести переменной ДАННЫЕ_ИГРЫ или
   GAMES_DATA, чтобы проверки писали во временную папку, а не в боевые
   данные). Своей копии пути здесь нет по той же причине, что и в
   server/рейтинг.js.
   ===================================================================== */

const fs = require('fs');
const crypto = require('crypto');
const гдеДанные = require('./папка-данных.js');
const реестр = require('../js/игры-реестр.js');
const { началоНедели } = require('./недельный-счёт');

/** Папка с данными прямо сейчас. */
function папка() { return гдеДанные.папка(); }

/** Наш файл памяти. */
function файл() { return гдеДанные.файл('лучший-счёт.json'); }

/** Временный файл, в который пишем перед переименованием (см. запись). */
function файлПокаПишем() { return файл() + '.пишем'; }

/* ЗАМЕДЛЕНИЕ НАКРУТКИ. Взято теми же числами, что у билетов партии с
   ботом (server/билеты.js, ВЫДАЧА_НЕ_ЧАЩЕ/СДАЧА_НЕ_ЧАЩЕ/СДАЧ_В_СУТКИ) —
   не своя отдельная защита, а согласованная с остальным сервером: если
   где-то через десять секунд, значит и здесь через десять секунд, чтобы
   правило было одно на весь проект и его не приходилось объяснять дважды. */
const ВЫДАЧА_НЕ_ЧАЩЕ = 10 * 1000;
const СДАЧА_НЕ_ЧАЩЕ = 40 * 1000;
const СДАЧ_В_СУТКИ = 20;

/* Через сколько запись игрока (карта «игроки», замедление выдачи/сдачи)
   можно стереть из памяти целиком — тот же приём и то же число, что у
   server/билеты.js (см. там же, ЗАПИСЬ_ИГРОКА_ЖИВЁТ): если с последней
   выдачи и сдачи прошло больше суток, календарный день уже сменился и
   счётчик «сдачЗаДень» обнулился бы сам при следующем обращении, а более
   короткие сроки (билет, замедление выдачи и сдачи) истекли и подавно.
   Двое суток — с запасом на границу часовых поясов и на то, что уборка
   не мгновенна. Без этой уборки карта «игроки» растёт бесконечно —
   утечка памяти на долгом процессе. */
const ЗАПИСЬ_ИГРОКА_ЖИВЁТ = 2 * 24 * 60 * 60 * 1000;

/* Не чаще раза в этот срок зовём уборку — лениво, при обращении к игроку,
   тем же приёмом, что в server/билеты.js: без setInterval, часы приходят
   тем же доводом «сейчас», что и в выдатьБилет()/принять(), и это же
   держит проверку дешёвой. */
const УБОРКА_ИГРОКОВ_НЕ_ЧАЩЕ = 10 * 60 * 1000;

let последняяУборкаИгроков = 0;

/* СРОК ЖИЗНИ БИЛЕТА. Головоломка может идти долго с перерывами (2048
   до высоких плиток — часы, судоку на сложном уровне — тоже не пять
   минут, и телефон за это время сворачивают). Взято 6 часов — как у
   самых долгих партий с ботом сейчас (катан, монополия, server/билеты.js,
   план раздел 2 пункт 5): дольше в одиночной головоломке нужно редко,
   а событие тут одно, не футбольный матч. Долгий срок жизни билета не
   ослабляет защиту по «заСекунду»: она отсекает СЛИШКОМ БЫСТРЫЙ счёт
   относительно прошедшего времени, а слишком МЕДЛЕННУЮ честную игру не
   трогает вовсе. От неправдоподобно большого счёта в любом случае
   отдельно бережёт потолок (счёт.потолок) — он не зависит от времени. */
const БИЛЕТ_ЖИВЁТ = 6 * 60 * 60 * 1000;

/* Допуск при сверке заявленного времени решения с часами сервера —
   секунды на сетевую задержку между концом партии в браузере и приходом
   запроса на сервер. Без допуска пограничная честная партия («решил
   ровно как истекло время билета») отказывалась бы по случайности сети. */
const ДОПУСК_ВРЕМЕНИ_СЕК = 5;

/* Потолок билетов в памяти разом — от затопления тысячами подписей
   (тот же приём и то же число, что у server/билеты.js). */
const ВСЕГО_НЕ_БОЛЬШЕ = 20000;

/* Билет: 128 случайных бит — угадать нельзя, перебирать бессмысленно
   (тот же вид, что у server/билеты.js). */
const ВИД_БИЛЕТА = /^[0-9a-f]{32}$/;

/** Одними словами отвечаем на любой непонятный курсор листания. */
const ОТКАЗ_КУРСОР = 'Не получилось показать продолжение списка: начните список заново';

/** Сколько строк отдаём за один срез() — как верхушка общего рейтинга. */
const СТРАНИЦА = 25;

/* Номер билета → { номер, игра, режим, выдан, зерно }. Map помнит
   порядок добавления — старые билеты стоят первыми. */
const билеты = new Map();

/* Номер игрока → { выдан, сдан, день, сдачЗаДень }: когда в последний
   раз брал и сдавал, и сколько сдач сегодня (замедление накрутки). */
const игроки = new Map();

/* Память результатов: игра → режим → номер → { номер, имя, значение, дата }.
   Три уровня, потому что таблицы разных игр и разных режимов одной игры
   не смешиваются — у судоку «Лёгкий» и «Эксперт» это разные рекорды. */
const результаты = new Map();

let записьРазрешена = false;
let ужеЗагрузили = false;
/* true между моментом изменения и попыткой записи. Нужен, чтобы
   дописать() (штатная остановка сервера) не затёрла файл пустыми
   данными, если сервер поднялся и остановился до первой сдачи или
   среза, — загрузка ленивая (см. ужеЗагрузили), и в памяти тогда пусто
   (тот же приём, что в server/друзья.js и server/знакомые.js). */
let естьЧтоЗаписать = false;

/** Разрешить запись на диск (сервер с «--без-памяти» её не включает). */
function включитьЗапись() {
  записьРазрешена = true;
}

function этоНомерИгрока(номер) {
  return Number.isInteger(номер) && номер > 0;
}

function отказ(причина) {
  return { ок: false, причина: причина };
}

/** «2026-09-29» по местному времени — как день у рейтинга и билетов. */
function ключДня(время) {
  const дата = new Date(время);
  return дата.getFullYear() + '-' + String(дата.getMonth() + 1).padStart(2, '0') + '-' +
         String(дата.getDate()).padStart(2, '0');
}

/** Имя как строка разумной длины — или пусто (как в server/рейтинг.js). */
function типИмени(имя) {
  if (typeof имя !== 'string') return '';
  const чистое = имя.trim();
  return чистое ? чистое.slice(0, 40) : '';
}

/** Запись игрока в памяти замедления; заводим по первому обращению. */
function игрок(номер) {
  if (!игроки.has(номер)) игроки.set(номер, { выдан: 0, сдан: 0, день: '', сдачЗаДень: 0 });
  return игроки.get(номер);
}

/** Убрать записи игроков, которые давно не выдавали и не сдавали билет:
 * ни на один лимит они больше не влияют, а место в памяти занимают
 * (перенесено из server/билеты.js — тот же приём). */
function убратьУстаревшихИгроков(сейчас) {
  for (const [номер, кто] of игроки) {
    const последнийРаз = Math.max(кто.выдан, кто.сдан);
    if (сейчас - последнийРаз > ЗАПИСЬ_ИГРОКА_ЖИВЁТ) игроки.delete(номер);
  }
}

/** Позвать уборку записей игроков, но не чаще раза в УБОРКА_ИГРОКОВ_НЕ_ЧАЩЕ. */
function позватьУборкуИгроков(сейчас) {
  if (сейчас - последняяУборкаИгроков < УБОРКА_ИГРОКОВ_НЕ_ЧАЩЕ) return;
  последняяУборкаИгроков = сейчас;
  убратьУстаревшихИгроков(сейчас);
}

/** Поле счёт этой игры из общего реестра, или null — у игры его нет. */
function конфигСчёта(игра) {
  const запись = реестр.поКлючу(игра);
  return (запись && запись.счёт) ? запись.счёт : null;
}

/** Описание режима в счёт.режимы этой игры, или null — режима нет. */
function найтиРежим(счётИгры, режим) {
  if (!счётИгры || typeof режим !== 'string') return null;
  for (const р of счётИгры.режимы) {
    if (р.ключ === режим) return р;
  }
  return null;
}

/* Поля потолок/заСекунду/неБыстрее — по правилу из js/игры-реестр.js
   (см. документацию поля счёт там же): либо одно число сразу на все
   режимы, либо объект { режим: число }, если у режимов разная сложность
   (так у судоку — эксперту нужен больший минимум времени, чем лёгкому).
   null — проверка этой мерой к игре не применяется. */
function значениеПоРежиму(поле, режим) {
  if (поле === null || поле === undefined) return null;
  if (typeof поле === 'number') return поле;
  if (typeof поле === 'object') {
    const значение = поле[режим];
    return typeof значение === 'number' ? значение : null;
  }
  return null;
}

