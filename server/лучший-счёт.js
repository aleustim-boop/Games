/** Убрать билеты старше срока жизни. */
function убратьПросроченные(сейчас) {
  for (const [ключ, запись] of билеты) {
    if (сейчас - запись.выдан > БИЛЕТ_ЖИВЁТ) билеты.delete(ключ);
  }
}

/**
 * Выдать билет на партию-головоломку.
 * Отвечает { ок: true, билет, зерно } или отказ словами.
 * Номер сюда приходит уже проверенный — из подписи Telegram.
 *
 * «Зерно» — случайное 32-битное целое, задел под будущий повтор партии
 * на сервере (план, этап Э4.9): сейчас оно просто лежит в билете и
 * возвращается игроку, но никак не проверяется.
 */
function выдатьБилет(номер, игра, режим, сейчас) {
  const когда = typeof сейчас === 'number' ? сейчас : Date.now();
  if (!этоНомерИгрока(номер)) return отказ('Рейтинг по счёту начисляется только в Telegram');

  const счётИгры = конфигСчёта(игра);
  if (!счётИгры) return отказ('У этой игры нет рейтинга по лучшему счёту');
  if (!найтиРежим(счётИгры, режим)) return отказ('Такого режима нет');

  // До создания записи текущего игрока — иначе свежую запись (выдан
  // ещё не проставлен) уборка сочтёт устаревшей и тут же сотрёт.
  позватьУборкуИгроков(когда);
  const кто = игрок(номер);
  if (кто.выдан && когда - кто.выдан < ВЫДАЧА_НЕ_ЧАЩЕ) {
    return отказ('Билет на партию — не чаще раза в десять секунд');
  }
  убратьПросроченные(когда);
  while (билеты.size >= ВСЕГО_НЕ_БОЛЬШЕ) билеты.delete(билеты.keys().next().value);

  const билет = crypto.randomBytes(16).toString('hex');
  const зерно = crypto.randomBytes(4).readUInt32BE(0);
  билеты.set(билет, { номер: номер, игра: игра, режим: режим, выдан: когда, зерно: зерно });
  кто.выдан = когда;
  return { ок: true, билет: билет, зерно: зерно };
}

/**
 * Принять результат партии по билету.
 *
 * значение — { счёт: число } для игр с мерой «очки» или { секунд: число }
 * для игр с мерой «время» (какая мера у игры — решает js/игры-реестр.js).
 * имя — как игрок назвался, для отображения в таблице (необязательно;
 * без него в новой записи останется то, что уже было, как у server/рейтинг.js).
 * сейчас — часы для проверок (необязательно, по умолчанию Date.now()) —
 * тот же приём, что и во всех функциях этого файла и в server/билеты.js.
 * Эти два довода прямо в тексте плана не названы (там короче: «принять(номер,
 * билет, {счёт|секунд})»), но нужны по смыслу: без имени срез() нечего
 * было бы показывать, без часов доводом проверки не могли бы подделывать
 * время — оба добавлены по образцу server/билеты.js «погасить(…, имя, сейчас)».
 *
 * Отвечает { ок: true, улучшение, значение } — значение это ЛУЧШИЙ
 * результат игрока после этой попытки (улучшение: true — это она и есть,
 * false — рекорд остался прежним, но партия честная) — либо отказ словами
 * для нечестного или непонятного результата.
 */
function принять(номер, билет, значение, имя, сейчас) {
  загрузитьЕслиНужно();
  const когда = typeof сейчас === 'number' ? сейчас : Date.now();
  if (!этоНомерИгрока(номер)) return отказ('Рейтинг по счёту начисляется только в Telegram');
  if (typeof билет !== 'string' || !ВИД_БИЛЕТА.test(билет)) return отказ('Билета на партию нет');

  const запись = билеты.get(билет);
  if (!запись) return отказ('Билета нет или он уже использован');
  // Чужой билет не гасим: номер билета знает только его хозяин.
  if (запись.номер !== номер) return отказ('Билет выдан другому игроку');

  /* С этого места билет использован при любом ответе: одна попытка на
     билет (тот же приём, что в server/билеты.js «погасить»). Иначе можно
     было бы слать неудачные попытки, пока не подойдёт нужное число. */
  билеты.delete(билет);

  const счётИгры = конфигСчёта(запись.игра);
  if (!счётИгры) return отказ('У этой игры нет рейтинга по лучшему счёту');
  if (!найтиРежим(счётИгры, запись.режим)) return отказ('Такого режима нет');

  if (когда - запись.выдан > БИЛЕТ_ЖИВЁТ) return отказ('Билет просрочен');
  const прошлоСекунд = Math.max(0, (когда - запись.выдан) / 1000);

  позватьУборкуИгроков(когда);
  const кто = игрок(номер);
  if (кто.сдан && когда - кто.сдан < СДАЧА_НЕ_ЧАЩЕ) {
    return отказ('Результат засчитывается не чаще раза в сорок секунд');
  }
  const сегодня = ключДня(когда);
  if (кто.день !== сегодня) {
    кто.день = сегодня;
    кто.сдачЗаДень = 0;
  }
  if (кто.сдачЗаДень >= СДАЧ_В_СУТКИ) {
    return отказ('На сегодня результатов засчитано достаточно — снова завтра');
  }

  let число;
  if (счётИгры.мера === 'очки') {
    if (!значение || typeof значение.счёт !== 'number' || !Number.isInteger(значение.счёт) || значение.счёт < 0) {
      return отказ('Счёт не понят');
    }
    число = значение.счёт;

    const потолок = значениеПоРежиму(счётИгры.потолок, запись.режим);
    if (потолок !== null && число > потолок) return отказ('Такой счёт для этой игры невозможен');

    const заСекунду = значениеПоРежиму(счётИгры.заСекунду, запись.режим);
    if (заСекунду !== null && число > 0) {
      // Math.max от деления на нуль — мгновенная сдача с положительным
      // счётом ловится тем же неравенством, а не отдельной веткой.
      const скорость = число / Math.max(прошлоСекунд, 0.001);
      if (скорость > заСекунду) return отказ('Счёт набран слишком быстро, чтобы быть честным');
    }
  } else if (счётИгры.мера === 'время') {
    if (!значение || typeof значение.секунд !== 'number' || !Number.isInteger(значение.секунд) || значение.секунд < 0) {
      return отказ('Время не понято');
    }
    число = значение.секунд;

    const потолок = значениеПоРежиму(счётИгры.потолок, запись.режим);
    if (потолок !== null && число > потолок) return отказ('Такое время для этой игры невозможно');

    const неБыстрее = значениеПоРежиму(счётИгры.неБыстрее, запись.режим);
    if (неБыстрее !== null && число < неБыстрее) {
      return отказ('Решить настолько быстро нельзя — результат недостоверен');
    }
    if (число > прошлоСекунд + ДОПУСК_ВРЕМЕНИ_СЕК) {
      return отказ('Заявленное время больше, чем прошло с начала партии');
    }
  } else {
    return отказ('У этой игры не настроена мера счёта');
  }

  кто.сдан = когда;
  кто.сдачЗаДень++;

  const итог = обновитьЕслиЛучше(запись.игра, запись.режим, номер, число, когда, счётИгры.лучше, имя);
  const результат = таблицаРезультатов(запись.игра, запись.режим).get(номер);
  const с = началоНедели(ключДня(когда));
  if (!результат.неделя || результат.неделя.с !== с || результатЛучше(счётИгры.лучше, число, результат.неделя.значение)) {
    результат.неделя = { с, значение: число };
  }
  записатьСрочно();
  return { ок: true, улучшение: итог.улучшение, значение: итог.значение };
}

/** Лучше ли новое значение старого — по направлению из реестра. */
function результатЛучше(лучше, новое, старое) {
  return лучше === 'меньше' ? новое < старое : новое > старое;
}

/**
 * Обновить лучший результат игрока, если новый честно лучше прежнего.
 * Отвечает { улучшение, значение } — значение это лучший результат
 * ПОСЛЕ этой попытки (новый, если улучшили, иначе прежний).
 */
function обновитьЕслиЛучше(игра, режим, номер, число, когда, лучше, имя) {
  const таблица = таблицаРезультатов(игра, режим);
  const был = таблица.get(номер);
  const чистоеИмя = типИмени(имя);

  if (был && !результатЛучше(лучше, число, был.значение)) {
    if (чистоеИмя) был.имя = чистоеИмя; // имя обновляем в любом случае — мог назваться иначе
    return { улучшение: false, значение: был.значение };
  }

  таблица.set(номер, {
    номер: номер,
    имя: чистоеИмя || (был ? был.имя : ''),
    значение: число,
    дата: ключДня(когда),
    неделя: был?.неделя || null
  });
  return { улучшение: true, значение: число };
}

/* ---------------------------------------------------------------------
   Что видит игрок
   --------------------------------------------------------------------- */

/** Все результаты игры/режима по порядку: лучший — первым. */
function порядокРезультатов(игра, режим, лучше) {
  const таблица = таблицаРезультатов(игра, режим);
  const список = Array.from(таблица.values());
  список.sort(function (а, б) {
    if (а.значение !== б.значение) {
      return лучше === 'меньше' ? а.значение - б.значение : б.значение - а.значение;
    }
    // При полном равенстве — устойчивый порядок, не зависящий от Map.
    return (а.номер || 0) - (б.номер || 0);
  });
  return список;
}

/**
 * Одна строка таблицы наружу. Собирается вручную, поле за полем —
 * номер Telegram остаётся здесь и наружу не уходит никогда (тот же
 * принцип, что в server/рейтинг.js, функция «строка»).
 */
function строкаНаружу(запись, место, этоЯ) {
  return {
    место: место,
    имя: запись.имя || 'Игрок',
    значение: запись.значение,
    дата: запись.дата,
    этоЯ: этоЯ === true
  };
}

/** Курсор листания: непрозрачная строка, клиент её не разбирает. */
function собратьКурсор(игра, режим, смещение) {
  return Buffer.from(JSON.stringify({ игра: игра, режим: режим, смещение: смещение }), 'utf8').toString('base64');
}

/** Разобрать курсор; чужой курсор (другая игра/режим) или мусор — null. */
function разобратьКурсор(продолжение, игра, режим) {
  try {
    const данные = JSON.parse(Buffer.from(продолжение, 'base64').toString('utf8'));
    if (!данные || данные.игра !== игра || данные.режим !== режим) return null;
    if (!Number.isInteger(данные.смещение) || данные.смещение < 0) return null;
    return данные;
  } catch (сбой) {
    return null;
  }
}

/**
 * Срез таблицы этой игры/режима: строки той же формы, что у общего
 * рейтинга (место, имя, значение, дата, этоЯ), но без номера наружу.
 * номер — кто спрашивает (чтобы пометить свою строку), продолжение —
 * курсор из прошлого ответа этой же функции, либо пусто для первой
 * страницы. Отвечает { ок: true, строки, продолжение } (продолжение —
 * null, если строк больше нет) или отказ словами.
 */
function срез(игра, режим, номер, продолжение) {
  загрузитьЕслиНужно();
  const счётИгры = конфигСчёта(игра);
  if (!счётИгры) return отказ('У этой игры нет рейтинга по лучшему счёту');
  if (!найтиРежим(счётИгры, режим)) return отказ('Такого режима нет');

  let начатьС = 0;
  if (продолжение) {
    const курсор = разобратьКурсор(продолжение, игра, режим);
    if (!курсор) return отказ(ОТКАЗ_КУРСОР);
    начатьС = курсор.смещение;
  }

  const список = порядокРезультатов(игра, режим, счётИгры.лучше);
  const порция = список.slice(начатьС, начатьС + СТРАНИЦА);
  const строки = порция.map(function (запись, индекс) {
    return строкаНаружу(запись, начатьС + индекс + 1, запись.номер === номер);
  });
  const конец = начатьС + порция.length;
  return {
    ок: true,
    строки: строки,
    продолжение: конец < список.length ? собратьКурсор(игра, режим, конец) : null
  };
}

