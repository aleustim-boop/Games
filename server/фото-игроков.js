'use strict';

/* =====================================================================
   Фото других игроков — закрытый модуль сервера (план: штаб/план-фото-
   игроков.md, «Главное» и «Этап 1»; правки по ревью — штаб/план-…, 23.09).

   Что делает. По номеру игрока в Telegram (наружу его отдавать нельзя —
   договор рейтинг.js:91-93, сервер.js:2654-2656) модуль умеет спросить
   у Bot API маленькую фотографию профиля и потом отдать её байты по
   непрозрачному ключу: снаружи виден только ключ (24 знака hex),
   обратно к номеру его превращает только этот модуль, в памяти.

   Как устроено:
     - ключДляНомера(номер) — HMAC-sha256 от номера на секрете, который
       рождается заново при каждом создать() (crypto.randomBytes). Номер
       можно передать числом или строкой из цифр — годится то, что после
       ключДляНомера превратится в тот же самый канонический вид. Карта
       «ключ → номер» держит не больше КЛЮЧЕЙ_МАКС записей, старые уходят
       первыми (обычный порядок вставки в Map); вместе с ключом уходит и
       его запись в кэше — иначе кэш растёт без счёта после вытеснения.
     - отдать(ключ) — по ключу находит номер, смотрит в кэш; кэша нет —
       идёт в Telegram: getUserProfilePhotos (самое маленькое фото) →
       getFile → скачивание с обрывом после ПРЕДЕЛ_БАЙТ. Одновременных
       походов в Telegram не больше ПАРАЛЛЕЛЬНО_МАКС; лишним — сразу null.
       Повторный запрос на тот же номер, пока первый ещё летит, получает
       тот же самый промис, а не второй поход.
     - умею() — есть ли токен вообще; без него отдать() всегда null.

   Труба и скачивание — доводами создать({токен, труба, скачать}). Без
   доводов труба и скачать настоящие: говорят с api.telegram.org через
   https, адрес с токеном живёт только внутри этих двух функций и никуда
   больше не попадает — ни в ошибку, ни в лог. Беды здесь молчат нарочно,
   тем же приёмом, что и в server/сервер.js у запросВTelegram (образец —
   строка ~1039 того файла). У обоих запросов: проверка статус-кода ДО
   чтения тела (404/401/редирект — не «фото»), слушатель ошибки и на
   запросе, и на самом теле ответа (обрыв соединения посреди тела — не
   исключение, которое роняет процесс, а обычный null), и общий таймер
   на весь запрос целиком — не только на паузы в передаче.
   ===================================================================== */

const crypto = require('crypto');
const https = require('https');

const ПРЕДЕЛ_БАЙТ = 64 * 1024;               // больше — не аватар, а история
const КЭШ_ЕСТЬ_НЕТ_МС = 24 * 60 * 60 * 1000;  // сутки: свой не меняет фото каждый час
const КЭШ_ОШИБКА_МС = 60 * 60 * 1000;         // час: вдруг Telegram отлежится
const ОБЪЁМ_КЭША_МАКС = 20 * 1024 * 1024;     // общий вес картинок в памяти
const КЛЮЧЕЙ_МАКС = 5000;                     // размер карты «ключ → номер» и кэша
const ПАРАЛЛЕЛЬНО_МАКС = 3;                   // одновременных походов в Telegram
const ЖДЁМ_TELEGRAM_МС = 5000;

const КЛЮЧ_РЕГ = /^[0-9a-f]{24}$/;
const ПУТЬ_РЕГ = /^[A-Za-z0-9_\-/.]{1,200}$/;
const НОМЕР_СТРОКОЙ_РЕГ = /^\d{1,20}$/;

/** Число из доводов создать(), если оно настоящее положительное число — иначе значение по умолчанию. */
function положительноеЧисло(значение, поУмолчанию) {
  return typeof значение === 'number' && значение > 0 ? значение : поУмолчанию;
}

/** Номер игрока к каноническому виду (строка без ведущих нулей) — или '', если не похож на номер. */
function каноничныйНомер(номер) {
  if (Number.isInteger(номер) && номер > 0) return String(номер);
  if (typeof номер === 'string' && НОМЕР_СТРОКОЙ_РЕГ.test(номер)) {
    const без0 = номер.replace(/^0+(?=\d)/, '');
    return без0 === '0' ? '' : без0;
  }
  return '';
}

/**
 * Создать отдельный экземпляр модуля. Каждый вызов — свой секрет и своя
 * память: несколько экземпляров в одном процессе (например, боевой и
 * проверочный) друг другу не мешают.
 *
 * @param {{токен?: string, труба?: Function, скачать?: Function}} настройки
 *   токен  — токен бота; пустой или отсутствует — модуль просто не умеет.
 *   труба  — (метод, тело) => Promise<ответ Bot API>; без довода — настоящий https.
 *   скачать — (file_path) => Promise<Buffer>; без довода — настоящий https.
 */
function создать(настройки) {
  настройки = настройки || {};
  const токен = typeof настройки.токен === 'string' ? настройки.токен : '';
  const труба = typeof настройки.труба === 'function' ? настройки.труба : спроситьTelegramНастоящий;
  const скачать = typeof настройки.скачать === 'function' ? настройки.скачать : скачатьНастоящий;

  /* Лимиты и сроки можно подменить доводом — только для проверок, чтобы не
     ждать настоящие сутки или 5 секунд. В бою server.js эти доводы не
     передаёт, и в дело идут значения по умолчанию сверху файла. */
  const пределБайт = положительноеЧисло(настройки.пределБайт, ПРЕДЕЛ_БАЙТ);
  const кэшЕстьНетМс = положительноеЧисло(настройки.кэшЕстьНетМс, КЭШ_ЕСТЬ_НЕТ_МС);
  const кэшОшибкаМс = положительноеЧисло(настройки.кэшОшибкаМс, КЭШ_ОШИБКА_МС);
  const объёмКэшаМакс = положительноеЧисло(настройки.объёмКэшаМакс, ОБЪЁМ_КЭША_МАКС);
  const ключейМакс = положительноеЧисло(настройки.ключейМакс, КЛЮЧЕЙ_МАКС);
  const параллельноМакс = положительноеЧисло(настройки.параллельноМакс, ПАРАЛЛЕЛЬНО_МАКС);
  const ждёмTelegramМс = положительноеЧисло(настройки.ждёмTelegramМс, ЖДЁМ_TELEGRAM_МС);

  const секрет = crypto.randomBytes(32);
  const ключИНомер = new Map();  // ключ (24 hex) → канонический номер (строка)
  const кэш = new Map();         // канонический номер → запись кэша ({статус, доКогда, байты?, тип?})
  const влёте = new Map();       // канонический номер → промис похода в Telegram, который ещё не завершился

  /** Есть ли у модуля токен — то есть умеет ли он вообще говорить с Telegram. */
  function умею() {
    return токен.length > 0;
  }

  /** Непрозрачный ключ для номера игрока (число или строка из цифр). Один номер — один ключ. */
  function ключДляНомера(номер) {
    const канон = каноничныйНомер(номер);
    if (!канон) return '';
    const ключ = crypto.createHmac('sha256', секрет).update(канон).digest('hex').slice(0, 24);
    if (!ключИНомер.has(ключ)) {
      ключИНомер.set(ключ, канон);
      while (ключИНомер.size > ключейМакс) {
        const самыйСтарыйКлюч = ключИНомер.keys().next().value;
        const уходящийНомер = ключИНомер.get(самыйСтарыйКлюч);
        ключИНомер.delete(самыйСтарыйКлюч);
        кэш.delete(уходящийНомер); // без ключа запись в кэше уже не достать — не копим мусор
      }
    }
    return ключ;
  }

  /** Байты фото по ключу — из кэша, либо новым походом в Telegram. Чужой/кривой ключ — сразу null. */
  function отдать(ключ) {
    if (!умею()) return Promise.resolve(null);
    if (typeof ключ !== 'string' || !КЛЮЧ_РЕГ.test(ключ)) return Promise.resolve(null);
    const номер = ключИНомер.get(ключ);
    if (!номер) return Promise.resolve(null);

    /* Кэш ещё живой — отдаём без похода в Telegram. */
    const запись = кэш.get(номер);
    if (запись && запись.доКогда > Date.now()) {
      return Promise.resolve(запись.статус === 'есть' ? { байты: запись.байты, тип: запись.тип } : null);
    }

    /* Тот же номер уже летит — не дублируем поход, ждём общий промис. */
    if (влёте.has(номер)) return влёте.get(номер);

    /* Лишним сверх лимита — сразу отказ, а не в очередь на потом. */
    if (влёте.size >= параллельноМакс) return Promise.resolve(null);

    const обещание = сходитьВTelegram(номер).finally(function () { влёте.delete(номер); });
    влёте.set(номер, обещание);
    return обещание;
  }

  /** Полный поход в Telegram за фото одного номера, с записью результата в кэш. */
  async function сходитьВTelegram(номер) {
    let ответФото;
    try {
      /* user_id у Bot API — число, а не строка (образец: server/сервер.js:1031);
         канон здесь всегда строка цифр без ведущих нулей, Number() её честно переводит. */
      ответФото = await труба('getUserProfilePhotos', { user_id: Number(номер), limit: 1, offset: 0 });
    } catch (сбой) {
      ответФото = null;
    }
    if (!ответФото || ответФото.ok !== true || !ответФото.result || !Array.isArray(ответФото.result.photos)) {
      запомнить(номер, 'ошибка', кэшОшибкаМс);
      return null;
    }

    const размеры = ответФото.result.photos[0];
    if (!Array.isArray(размеры) || размеры.length === 0) {
      запомнить(номер, 'нет', кэшЕстьНетМс);
      return null;
    }

    const самоеМаленькое = размеры[0];
    const fileId = самоеМаленькое && самоеМаленькое.file_id;
    if (typeof fileId !== 'string' || !fileId) {
      запомнить(номер, 'ошибка', кэшОшибкаМс);
      return null;
    }

    let ответФайла;
    try {
      ответФайла = await труба('getFile', { file_id: fileId });
    } catch (сбой) {
      ответФайла = null;
    }
    if (!ответФайла || ответФайла.ok !== true || !ответФайла.result) {
      запомнить(номер, 'ошибка', кэшОшибкаМс);
      return null;
    }

    const путь = ответФайла.result.file_path;
    const размерФайла = ответФайла.result.file_size;
    if (typeof размерФайла === 'number' && размерФайла > пределБайт) {
      запомнить(номер, 'нет', кэшЕстьНетМс);
      return null;
    }
    if (typeof путь !== 'string' || !ПУТЬ_РЕГ.test(путь) || путь.indexOf('..') !== -1) {
      запомнить(номер, 'ошибка', кэшОшибкаМс);
      return null;
    }

    let байты;
    try {
      байты = await скачать(путь);
    } catch (сбой) {
      байты = null;
    }
    if (!Buffer.isBuffer(байты)) {
      /* Скачивание не удалось (таймаут, обрыв, статус не 200) — это не то же
         самое, что «у игрока нет такого файла»: Telegram мог просто
         отлежаться, короткий срок кэша даёт быстро попробовать снова. */
      запомнить(номер, 'ошибка', кэшОшибкаМс);
      return null;
    }
    if (байты.length === 0 || байты.length > пределБайт) {
      запомнить(номер, 'нет', кэшЕстьНетМс);
      return null;
    }

    запомнить(номер, 'есть', кэшЕстьНетМс, байты);
    return { байты: байты, тип: 'image/jpeg' };
  }

  function запомнить(номер, статус, наСколькоМс, байты) {
    чиститьПросроченные();
    if (статус === 'есть') {
      кэш.set(номер, { статус: 'есть', байты: байты, тип: 'image/jpeg', доКогда: Date.now() + наСколькоМс });
      подрезатьОбъём();
    } else {
      кэш.set(номер, { статус: статус, доКогда: Date.now() + наСколькоМс });
    }
    /* Число записей тоже не без счёта: старые (по порядку вставки) уходят первыми. */
    while (кэш.size > ключейМакс) {
      кэш.delete(кэш.keys().next().value);
    }
  }

  /* Записи с истёкшим сроком не ждут своей очереди на перезапись — убираем сразу. */
  function чиститьПросроченные() {
    const сейчас = Date.now();
    for (const [номер, запись] of кэш) {
      if (запись.доКогда <= сейчас) кэш.delete(номер);
    }
  }

  /* Держим общий вес картинок в кэше не больше объёмКэшаМакс: самые
     старые записи «есть» уходят первыми, пока вес не влезет в предел. */
  function подрезатьОбъём() {
    let вес = 0;
    for (const запись of кэш.values()) {
      if (запись.статус === 'есть') вес += запись.байты.length;
    }
    if (вес <= объёмКэшаМакс) return;
    for (const [номер, запись] of кэш) {
      if (вес <= объёмКэшаМакс) break;
      if (запись.статус !== 'есть') continue;
      вес -= запись.байты.length;
      кэш.delete(номер);
    }
  }

  /** Настоящий запрос в Bot API — POST, без единого слова в лог при беде. */
  function спроситьTelegramНастоящий(метод, тело) {
    return new Promise(function (готово) {
      let ответили = false;
      let общийТаймер = null;
      function закончить(что) {
        if (ответили) return;
        ответили = true;
        if (общийТаймер) clearTimeout(общийТаймер);
        готово(что);
      }
      const данные = Buffer.from(JSON.stringify(тело), 'utf8');
      const запрос = https.request({
        hostname: 'api.telegram.org',
        path: '/bot' + токен + '/' + метод,
        method: 'POST',
        headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
      }, function (ответ) {
        /* Слушатель ошибки — первой строкой: обрыв тела не должен стать исключением
           без обработчика (которое роняет весь процесс), а обычным null. */
        ответ.on('error', function () { закончить(null); });
        /* Статус смотрим ДО чтения тела: чужой ответ (404/401/…) не пытаемся разобрать как JSON. */
        if (ответ.statusCode !== 200) { ответ.resume(); закончить(null); return; }
        let куски = '';
        ответ.setEncoding('utf8');
        ответ.on('data', function (кусок) { куски += кусок; });
        ответ.on('end', function () {
          try { закончить(JSON.parse(куски)); } catch (сбой) { закончить(null); }
        });
      });
      запрос.on('error', function () { закончить(null); });
      запрос.setTimeout(ждёмTelegramМс, function () { запрос.destroy(); закончить(null); });
      /* Таймер setTimeout у запроса реагирует только на тишину в сокете — если байты
         тихонько капают весь день, он не сработает. Этот таймер общий, на весь запрос. */
      общийТаймер = setTimeout(function () { запрос.destroy(); закончить(null); }, ждёмTelegramМс);
      if (общийТаймер.unref) общийТаймер.unref();
      запрос.write(данные);
      запрос.end();
    });
  }

  /** Настоящее скачивание файла — GET, обрыв сразу после пределБайт. */
  function скачатьНастоящий(путьКФайлу) {
    return new Promise(function (готово) {
      let ответили = false;
      let общийТаймер = null;
      function закончить(что) {
        if (ответили) return;
        ответили = true;
        if (общийТаймер) clearTimeout(общийТаймер);
        готово(что);
      }
      const запрос = https.get({
        hostname: 'api.telegram.org',
        path: '/file/bot' + токен + '/' + путьКФайлу
      }, function (ответ) {
        /* Слушатель ошибки — первой строкой, тем же приёмом, что и у POST выше. */
        ответ.on('error', function () { закончить(null); });
        /* Статус смотрим ДО чтения тела: 404/401/редирект — не фото, а страница ошибки,
           и в кэш «фото есть» она попадать не должна. */
        if (ответ.statusCode !== 200) { ответ.resume(); закончить(null); return; }
        const куски = [];
        let получено = 0;
        ответ.on('data', function (кусок) {
          куски.push(кусок);
          получено += кусок.length;
          if (получено > пределБайт) {
            ответ.destroy();
            закончить(Buffer.concat(куски));
          }
        });
        ответ.on('end', function () { закончить(Buffer.concat(куски)); });
      });
      запрос.on('error', function () { закончить(null); });
      запрос.setTimeout(ждёмTelegramМс, function () { запрос.destroy(); закончить(null); });
      /* Таймер setTimeout у запроса реагирует только на тишину — этот общий, на весь запрос. */
      общийТаймер = setTimeout(function () { запрос.destroy(); закончить(null); }, ждёмTelegramМс);
      if (общийТаймер.unref) общийТаймер.unref();
    });
  }

  return { ключДляНомера: ключДляНомера, отдать: отдать, умею: умею };
}

module.exports = { создать: создать };
