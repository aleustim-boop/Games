'use strict';

/* =====================================================================
   Учёт приглашений «Сыграть с другом» (план: штаб/план-сыграть-с-другом.md,
   этап Э5, раздел 2.3).

   Зачем. Владелец хочет знать, доходят ли приглашения до дела: сколько
   раз человек открыл окно выбора чата, сколько раз правда отправил,
   сколько друзей по ссылке сели за стол, начали и доиграли партию.
   Раньше признак «по приглашению» присылала сама игра, и проверить его
   было нечем. Теперь у каждого приглашения свой номер, который выдаёт
   сервер, а события к нему пишутся двумя руками:

     со слов игры (помечаются соСловКлиента: true):
       окноОткрыто, скопировано, отправлено, отменено —
       только от того, кто приглашение создал (по подписи Telegram);
     только сервер, по факту в комнатах (server/комнаты.js):
       вход, старт, итог — клиент прислать их не может вовсе;
     только сервер, по отказу двери /войти (server/сервер.js):
       отказВхода с причиной — друг пришёл по ссылке, а сесть не смог;
     сам этот файл:
       создано — при выдаче номера;
       комнатаПотеряна — при старте нового сервера: комнаты живут
       в памяти и пропадают при перезапуске, и незакрытая запись честно
       показывает, что приглашение сгорело не по вине человека.

   Что храним: номер Telegram пригласившего (из проверенной подписи),
   игру, код стола, время создания комнаты и события. Имён нет. Номера
   друзей в событиях «вход/старт/итог» — только чтобы не считать одного
   человека дважды. Файл лежит в папке данных (server/папка-данных.js),
   в git не едет, пишется отложенно и через временный файл — как
   статистика.js. Хранится 60 дней: и записи, и список «уже звали»
   (номера друзей) — тот же срок, считая от создания записи / отметки друга.

   Тестовые люди. Список номеров Telegram — файл тестовые.json в той же
   папке данных (массив чисел; заполняет владелец или штаб, в git он не
   кладётся). Приглашение такого человека пишется с тест: true, и отчёт
   по учёту его не считает.
   ===================================================================== */

const fs = require('fs');
const крипто = require('crypto');
const гдеДанные = require('./папка-данных.js');

/** Наш файл памяти. Путь спрашиваем каждый раз — см. папка-данных.js. */
function файл() { return гдеДанные.файл('приглашения.json'); }
function файлПокаПишем() { return файл() + '.пишем'; }
function файлБитый() { return файл() + '.битый'; }
function файлТестовых() { return гдеДанные.файл('тестовые.json'); }

const ХРАНИМ_ДНЕЙ = 60;
const ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ = 5000;

/* Потолки против раздувания памяти: одна запись не копит событий без
   конца (игра может слать «окноОткрыто» на каждое нажатие), а всего
   записей не больше, чем реально бывает приглашений за два месяца. */
const СОБЫТИЙ_В_ЗАПИСИ = 60;
const СОБЫТИЙ_СО_СЛОВ_КЛИЕНТА = 20;
const ЗАПИСЕЙ_ВСЕГО = 20000;

/* Предел на одного человека: без него один нажимающий «Позвать» без
   остановки (пауза двери — 3 секунды) за сутки вытеснил бы из общего
   потолка записи всех остальных. 50 приглашений в сутки живому человеку
   хватает с запасом; сверх — новых записей нет, а на тот же стол
   отдаётся его последний номер (ссылка с ним и так уже у друзей).
   Считаются только записи, где человек что-то сделал (см. былоДействие). */
const ПРИГЛАШЕНИЙ_НА_ЧЕЛОВЕКА_В_СУТКИ = 50;
const СУТКИ = 24 * 60 * 60 * 1000;

/* Какие события кто вправе ставить. Списки закрытые: всё, чего в них
   нет, отвергается. */
const СОБЫТИЯ_КЛИЕНТА = ['окноОткрыто', 'скопировано', 'отправлено', 'отменено'];
const СОБЫТИЯ_СЕРВЕРА = ['вход', 'старт', 'итог'];

/* Друг пришёл по ссылке, а за стол его не пустили. Причина — машинное
   слово отказа из server/комнаты.js (войтиВКомнату, поле «почему»):
   по ним видно, сколько друзей упёрлось и во что. Список закрытый. */
const ОТКАЗ_ВХОДА = 'отказВхода';
const ПРИЧИНЫ_ОТКАЗА = ['идёт', 'заполнена', 'закрыта', 'нет'];

/* Отказов в одной записи держим мало: иначе злой запрос с чужим номером
   забил бы запись до потолка СОБЫТИЙ_В_ЗАПИСИ, и настоящие «старт» и
   «итог» туда бы уже не влезли. Один человек с одной причиной — один раз. */
const ОТКАЗОВ_В_ЗАПИСИ = 10;

/* Номер приглашения: 8 строчных латинских букв и цифр. Такой номер
   проходит и новое правило ссылки («метка_КОД_ИД», 4–16 букв и цифр),
   и прежний хвост «.id» (ровно 8 строчных) — если где-то он ещё живёт. */
const ДЛИНА_НОМЕРА = 8;
const АЗБУКА = 'abcdefghijklmnopqrstuvwxyz0123456789';
const ГОДНЫЙ_НОМЕР = /^[A-Za-z0-9]{4,16}$/;

/* Когда запущен этот процесс. Запись, чья комната создана раньше, —
   от прошлого запуска: её комнаты уже нет в памяти. */
const СТАРТ_ПРОЦЕССА = Date.now();

/** номер → запись. Map помнит порядок: старые впереди. */
const записи = new Map();

/* Друзья, чей первый приход по зову уже передан слушателям (Э3 плана
   «Позвать друга»). Хранится в том же файле, что и записи, с тем же
   сроком ХРАНИМ_ДНЕЙ (60 дней) от момента отметки: номера Telegram
   дольше срока не держим. Чистится при загрузке, записи и создании. */
const позванныеДрузья = new Map();   // номер друга → когда отмечен (мс)
const слушателиВходов = [];

let ужеЗагрузили = false;
let записьРазрешена = false;
let естьЧтоЗаписать = false;
let таймерЗаписи = null;

/** На диск пишет только настоящий сервер (как у статистики). */
function включитьЗапись() {
  записьРазрешена = true;
  if (естьЧтоЗаписать) записатьПогодя();
}

function этоНомерИгрока(номер) {
  return Number.isInteger(номер) && номер > 0;
}

/* ---------------------------------------------------------------------
   Чтение и запись файла
   --------------------------------------------------------------------- */

/** Событие с диска — только знакомые поля, чужое выбрасываем. */
function чистоеСобытие(сырое) {
  if (!сырое || typeof сырое.что !== 'string') return null;
  const что = сырое.что;
  const годное = что === 'создано' || что === 'комнатаПотеряна' || что === ОТКАЗ_ВХОДА ||
    СОБЫТИЯ_КЛИЕНТА.indexOf(что) !== -1 || СОБЫТИЯ_СЕРВЕРА.indexOf(что) !== -1;
  if (!годное) return null;
  if (что === ОТКАЗ_ВХОДА && ПРИЧИНЫ_ОТКАЗА.indexOf(сырое.причина) === -1) return null;
  const когда = Number(сырое.когда);
  if (!Number.isFinite(когда) || когда <= 0) return null;
  const событие = { что: что, когда: когда };
  if (сырое.соСловКлиента === true) событие.соСловКлиента = true;
  if (typeof сырое.место === 'string' && сырое.место.length <= 20) событие.место = сырое.место;
  if (этоНомерИгрока(Number(сырое.кто))) событие.кто = Number(сырое.кто);
  if (typeof сырое.доиграна === 'boolean') событие.доиграна = сырое.доиграна;
  if (что === ОТКАЗ_ВХОДА) событие.причина = сырое.причина;
  return событие;
}

/** Запись с диска — поле за полем; негодная — null. */
function чистаяЗапись(сырая) {
  if (!сырая || typeof сырая !== 'object') return null;
  const кто = Number(сырая.кто);
  const создано = Number(сырая.создано);
  if (!этоНомерИгрока(кто) || !Number.isFinite(создано)) return null;
  const события = (Array.isArray(сырая.события) ? сырая.события : [])
    .map(чистоеСобытие).filter(Boolean).slice(0, СОБЫТИЙ_В_ЗАПИСИ);
  const запись = {
    создано: создано,
    кто: кто,
    игра: typeof сырая.игра === 'string' ? сырая.игра.slice(0, 40) : '',
    код: typeof сырая.код === 'string' ? сырая.код.slice(0, 12) : '',
    комнатаСоздана: Number.isFinite(Number(сырая.комнатаСоздана)) ? Number(сырая.комнатаСоздана) : создано,
    события: события
  };
  if (сырая.тест === true) запись.тест = true;
  return запись;
}

/**
 * Прочитать память с диска и закрыть то, что осталось от прошлого запуска.
 * Файла нет или он испорчен — начинаем с чистого листа: учёт не стоит
 * того, чтобы ронять сервер с партиями.
 */
function загрузить() {
  if (ужеЗагрузили) return;
  ужеЗагрузили = true;
  let прочитанное = null;
  try {
    прочитанное = JSON.parse(fs.readFileSync(файл(), 'utf8'));
  } catch (сбой) {
    прочитанное = null;
    /* Файл есть, но не читается — не затираем его первой же записью,
       а откладываем в сторону: по нему потом можно понять, что стряслось
       и что было в учёте. Файла нет вовсе — это просто первый запуск. */
    if (сбой && сбой.code !== 'ENOENT') отложитьБитый();
  }
  if (прочитанное && прочитанное.записи && typeof прочитанное.записи === 'object') {
    for (const номер of Object.keys(прочитанное.записи)) {
      if (!ГОДНЫЙ_НОМЕР.test(номер)) continue;
      const запись = чистаяЗапись(прочитанное.записи[номер]);
      if (запись) записи.set(номер, запись);
    }
  }
  if (прочитанное && Array.isArray(прочитанное.друзья)) {
    for (const сырой of прочитанное.друзья) {
      /* Новый вид — { друг, когда }; старый файл хранил просто номер:
         его срок считаем с загрузки (время отметки тогда не писали). */
      const друг = сырой && typeof сырой === 'object' ? Number(сырой.друг) : Number(сырой);
      const когда = сырой && typeof сырой === 'object' ? Number(сырой.когда) : Date.now();
      if (этоНомерИгрока(друг) && Number.isFinite(когда) && когда > 0) позванныеДрузья.set(друг, когда);
    }
  }
  прибраться();
  закрытьПотерянные();
}

/** Битый файл — в приглашения.json.битый (прежний битый заменяется). */
function отложитьБитый() {
  try {
    fs.renameSync(файл(), файлБитый());
  } catch (сбой) {
    /* Не вышло — начнём с чистого листа всё равно: учёт не роняет сервер. */
  }
}

/** Сложить память в файл. Молча: беда с диском не повод ронять партии. */
function записатьСейчас() {
  прибратьДрузей();
  const всё = {};
  for (const [номер, запись] of записи) всё[номер] = запись;
  try {
    fs.mkdirSync(гдеДанные.папка(), { recursive: true });
    fs.writeFileSync(файлПокаПишем(), JSON.stringify({
      записи: всё,
      друзья: Array.from(позванныеДрузья, function (п) { return { друг: п[0], когда: п[1] }; })
    }), 'utf8');
    fs.renameSync(файлПокаПишем(), файл());
    /* Флаг снимаем только теперь, когда файл правда на месте: иначе сбой
       диска молча терял бы изменения до следующего события. */
    естьЧтоЗаписать = false;
  } catch (сбой) {
    /* Не записалось — флаг остаётся, и следующая запись (или дописать при
       остановке) попробует снова. */
  }
}

function записатьПогодя() {
  естьЧтоЗаписать = true;
  if (!записьРазрешена || таймерЗаписи !== null) return;
  таймерЗаписи = setTimeout(function () {
    таймерЗаписи = null;
    if (естьЧтоЗаписать) записатьСейчас();
  }, ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ);
  if (таймерЗаписи.unref) таймерЗаписи.unref();
}

/** Записать прямо сейчас, если было что (остановка сервера, проверки). */
function дописать() {
  if (таймерЗаписи !== null) {
    clearTimeout(таймерЗаписи);
    таймерЗаписи = null;
  }
  if (записьРазрешена && естьЧтоЗаписать) записатьСейчас();
}

/* ---------------------------------------------------------------------
   Сам учёт
   --------------------------------------------------------------------- */

/** Забыть друзей, отмеченных раньше срока ХРАНИМ_ДНЕЙ. */
function прибратьДрузей() {
  const самоеСтарое = Date.now() - ХРАНИМ_ДНЕЙ * 24 * 60 * 60 * 1000;
  for (const [друг, когда] of позванныеДрузья) {
    if (когда < самоеСтарое) позванныеДрузья.delete(друг);                      // проверка:срок-друзей
  }
}

/** Выбросить записи старше срока и лишние сверх потолка (старые первыми). */
function прибраться() {
  прибратьДрузей();
  const самоеСтарое = Date.now() - ХРАНИМ_ДНЕЙ * 24 * 60 * 60 * 1000;
  for (const [номер, запись] of записи) {
    if (запись.создано < самоеСтарое) записи.delete(номер);
  }
  while (записи.size > ЗАПИСЕЙ_ВСЕГО) {
    записи.delete(записи.keys().next().value);
  }
}

/** Закрыта ли запись: партия доиграна или комната пропала при перезапуске. */
function закрыта(запись) {
  return запись.события.some(function (событие) {
    return событие.что === 'итог' || событие.что === 'комнатаПотеряна';
  });
}

/**
 * Комнаты прошлого запуска пропали вместе с его памятью. Незакрытые
 * записи от них закрываем событием «комнатаПотеряна» — по нему видно,
 * сколько приглашений сгорело от перезапуска сервера.
 */
function закрытьПотерянные() {
  let закрыто = 0;
  for (const запись of записи.values()) {
    if (закрыта(запись) || запись.комнатаСоздана >= СТАРТ_ПРОЦЕССА) continue;
    добавитьСобытие(запись, { что: 'комнатаПотеряна', когда: Date.now() });
    закрыто++;
  }
  if (закрыто > 0) записатьПогодя();
  return закрыто;
}

/** Есть ли в записи событие с таким именем. */
function есть(запись, что) {
  return запись.события.some(function (событие) { return событие.что === что; });
}

/* Действия человека, после которых запись — настоящее приглашение, а не
   номер, выданный заранее при показе кода стола. */
const ДЕЙСТВИЯ_ПРИГЛАШЕНИЯ = ['окноОткрыто', 'скопировано', 'отправлено'];

/** Было ли у записи хоть одно действие клиента из ДЕЙСТВИЯ_ПРИГЛАШЕНИЯ. */
function былоДействие(запись) {
  return запись.события.some(function (событие) {
    return ДЕЙСТВИЯ_ПРИГЛАШЕНИЯ.indexOf(событие.что) !== -1;
  });
}

function добавитьСобытие(запись, событие) {
  if (запись.события.length >= СОБЫТИЙ_В_ЗАПИСИ) return false;
  запись.события.push(событие);
  return true;
}

/** Тестовые номера из файла. Файла нет — тестовых нет. */
function тестовыеНомера() {
  try {
    const список = JSON.parse(fs.readFileSync(файлТестовых(), 'utf8'));
    return Array.isArray(список) ? список.map(Number).filter(этоНомерИгрока) : [];
  } catch (сбой) {
    return [];
  }
}

function новыйНомер() {
  for (;;) {
    const байты = крипто.randomBytes(ДЛИНА_НОМЕРА);
    let номер = '';
    for (let и = 0; и < ДЛИНА_НОМЕРА; и++) номер += АЗБУКА[байты[и] % АЗБУКА.length];
    if (!записи.has(номер)) return номер;
  }
}

/**
 * Завести приглашение. кто — номер Telegram из ПРОВЕРЕННОЙ подписи
 * (сервер.js), игра и код — стола, за который зовут, комнатаСоздана —
 * время рождения этой комнаты. Возвращает номер приглашения или ''.
 */
function создать(кто, игра, код, комнатаСоздана) {
  загрузить();
  if (!этоНомерИгрока(кто)) return '';
  const сейчас = Date.now();
  const стол = String(код || '').slice(0, 12);
  const родилась = Number.isFinite(комнатаСоздана) ? комнатаСоздана : сейчас;
  /* Номер игра просит заранее, при каждом показе кода стола, — ещё до того,
     как человек что-то нажал. Такая холостая запись приглашением не стала,
     поэтому дневной предел её не считает. А чтобы холостые записи не копились
     сами, холостую запись этого же стола отдаём снова, вместо новой. */
  const создалЗаСутки = [];
  for (const [прежний, запись] of записи) {
    if (запись.кто !== кто || запись.создано <= сейчас - СУТКИ) continue;
    if (!былоДействие(запись)) {
      if (запись.код === стол && запись.комнатаСоздана === родилась) return прежний;
      continue;
    }
    создалЗаСутки.push(прежний);
  }
  if (создалЗаСутки.length >= ПРИГЛАШЕНИЙ_НА_ЧЕЛОВЕКА_В_СУТКИ) {
    // Сверх предела — последний его номер для этого же стола, иначе ничего.
    for (let и = создалЗаСутки.length - 1; и >= 0; и--) {
      const запись = записи.get(создалЗаСутки[и]);
      if (запись.код === стол && запись.комнатаСоздана === родилась) return создалЗаСутки[и];
    }
    return '';
  }
  const номер = новыйНомер();
  const запись = {
    создано: сейчас,
    кто: кто,
    игра: String(игра || '').slice(0, 40),
    код: String(код || '').slice(0, 12),
    комнатаСоздана: родилась,
    события: [{ что: 'создано', когда: сейчас }]
  };
  if (тестовыеНомера().indexOf(кто) !== -1) запись.тест = true;
  записи.set(номер, запись);
  прибраться();
  записатьПогодя();
  return номер;
}

/**
 * Событие со слов игры: { ок } или { ок: false, почему }.
 * почему: 'что' — такого события игра ставить не вправе;
 *         'чужое' — номера нет или приглашение создал другой человек
 *         (намеренно одно слово на оба случая: чужому незачем знать,
 *         существует ли такой номер).
 */
function отметитьСоСловКлиента(номер, кто, что) {
  загрузить();
  if (СОБЫТИЯ_КЛИЕНТА.indexOf(что) === -1) return { ок: false, почему: 'что' };
  const запись = typeof номер === 'string' ? записи.get(номер) : null;
  if (!запись || !этоНомерИгрока(кто) || запись.кто !== кто) return { ок: false, почему: 'чужое' };
  const сословКлиента = запись.события.filter(function (с) { return с.соСловКлиента; }).length;
  if (сословКлиента >= СОБЫТИЙ_СО_СЛОВ_КЛИЕНТА) return { ок: true };   // молча: потолок, не ошибка
  /* Отправить одно приглашение можно лишь однажды: повторная отметка
     (игра повторила запрос, человек нажал дважды) учёт не множит. */
  if (что === 'отправлено' && есть(запись, 'отправлено')) return { ок: true };
  добавитьСобытие(запись, { что: что, когда: Date.now(), соСловКлиента: true });
  записатьПогодя();
  return { ок: true };
}

/**
 * Событие по факту в комнатах: вход / старт / итог. Зовёт только
 * server/комнаты.js. подробности: { место, кто, доиграна }. Одно и то же
 * событие для одного места и человека пишется один раз: реванш —
 * это не второй приход друга.
 */
function отметитьСервером(номер, что, подробности) {
  загрузить();
  if (СОБЫТИЯ_СЕРВЕРА.indexOf(что) === -1) return false;
  const запись = typeof номер === 'string' ? записи.get(номер) : null;
  if (!запись) return false;
  const п = подробности || {};
  const место = typeof п.место === 'string' ? п.место : '';
  const кто = этоНомерИгрока(п.кто) ? п.кто : null;
  const уже = запись.события.some(function (с) {
    return с.что === что && (с.место || '') === место && (с.кто || null) === кто;
  });
  if (уже) return false;
  const событие = { что: что, когда: Date.now() };
  if (место) событие.место = место;
  if (кто) событие.кто = кто;
  if (typeof п.доиграна === 'boolean') событие.доиграна = п.доиграна;
  добавитьСобытие(запись, событие);
  записатьПогодя();
  if (что === 'вход') сообщитьОПервомПриходе(запись, кто);
  return true;
}

/** Подписаться на первый приход друга по зову: функция(друг, пригласивший, игра, тест). */
function слушатьВходы(функция) {
  if (typeof функция === 'function') слушателиВходов.push(функция);
}

/**
 * Первый приход этого друга за всё время — зовём слушателей. Повтор
 * (реванш, второй стол, другой пригласивший) и «сам себя» — тишина.
 * Слушатель упал — учёт не страдает.
 */
function сообщитьОПервомПриходе(запись, друг) {
  if (!друг || друг === запись.кто || позванныеДрузья.has(друг)) return;
  /* Слушателей нет — никто не узнал о приходе, значит «первым» он ещё не
     был: не отмечаем, иначе подписавшийся позже слушатель его не увидит. */
  if (слушателиВходов.length === 0) return;                                     // проверка:нет-слушателей
  позванныеДрузья.set(друг, Date.now());
  записатьПогодя();
  for (const слушатель of слушателиВходов.slice()) {
    try {
      слушатель(друг, запись.кто, запись.игра, запись.тест === true);
    } catch (сбой) {
      /* Ошибка чужого слушателя не должна ронять комнаты. */
    }
  }
}

/**
 * Вход откатили (server/комнаты.js, отменитьВход): ответа человек не
 * получил, и за столом его нет. Снимаем записанные на это место «вход»
 * и «старт» (у стола на двоих карты раздаются прямо при входе) — иначе
 * учёт считал бы пришедшим того, кто не пришёл.
 */
function снятьВход(номер, место, кто) {
  загрузить();
  const запись = typeof номер === 'string' ? записи.get(номер) : null;
  if (!запись || typeof место !== 'string') return false;
  const человек = этоНомерИгрока(кто) ? кто : null;
  const было = запись.события.length;
  запись.события = запись.события.filter(function (с) {
    const этогоМеста = (с.что === 'вход' || с.что === 'старт') &&
      (с.место || '') === место && (с.кто || null) === человек;
    return !этогоМеста;
  });
  if (запись.события.length === было) return false;
  записатьПогодя();
  return true;
}

/** Код стола так же, как его приводит server/комнаты.js (привестиКод). */
function привестиКодСтола(что) {
  if (typeof что !== 'string') return '';
  return что.toUpperCase().replace(/[^A-Z0-9]/g, '').slice(0, 12);
}

/**
 * Друг вошёл по ссылке с этим номером и получил отказ. Зовёт сервер.js
 * (дверь /войти). код — стол из запроса, кто — номер Telegram из
 * ПРОВЕРЕННОЙ подписи, почему — машинное слово отказа.
 *
 * Злые запросы учёт не портят: номер должен быть настоящим и выданным
 * именно за этот стол (чужой номер к другому коду не прилипнет), гость —
 * с подписью и не сам пригласивший, причина — из закрытого списка.
 * Повтор того же человека с той же причиной не множит счёт.
 */
function отметитьОтказВхода(номер, код, кто, почему) {
  загрузить();
  if (typeof номер !== 'string' || !ГОДНЫЙ_НОМЕР.test(номер)) return false;
  if (ПРИЧИНЫ_ОТКАЗА.indexOf(почему) === -1 || !этоНомерИгрока(кто)) return false;
  const запись = записи.get(номер);
  if (!запись || запись.кто === кто) return false;
  const стол = привестиКодСтола(код);
  if (!стол || стол !== привестиКодСтола(запись.код)) return false;
  const отказы = запись.события.filter(function (с) { return с.что === ОТКАЗ_ВХОДА; });
  if (отказы.length >= ОТКАЗОВ_В_ЗАПИСИ) return false;
  const уже = отказы.some(function (с) { return с.кто === кто && с.причина === почему; });
  if (уже) return false;
  if (!добавитьСобытие(запись, { что: ОТКАЗ_ВХОДА, когда: Date.now(), кто: кто, причина: почему })) return false;
  записатьПогодя();
  return true;
}

/** Номер Telegram того, кто создал приглашение, или null (номера нет). */
function ктоСоздал(номер) {
  загрузить();
  const найдено = typeof номер === 'string' ? записи.get(номер) : null;
  return найдено ? найдено.кто : null;
}

/** Копия записи (для проверок и отчёта) или null. */
function запись(номер) {
  загрузить();
  const найдено = записи.get(номер);
  return найдено ? JSON.parse(JSON.stringify(найдено)) : null;
}

/** Сколько событий с таким именем в записи (для сводки). */
function сколько(запись, что) {
  return запись.события.filter(function (событие) { return событие.что === что; }).length;
}

/** Пустая строка сводки: одни нули. */
function пустаяСтрока() {
  return {
    приглашений: 0, окноОткрыто: 0, отправлено: 0, скопировано: 0,
    другСел: 0, партияНачата: 0, доиграли: 0, сгорело: 0
  };
}

/** Прибавить одну запись к строке сводки: каждая цифра — число записей, не событий. */
function прибавитьЗапись(строка, запись) {
  строка.приглашений++;
  if (есть(запись, 'окноОткрыто')) строка.окноОткрыто++;
  if (есть(запись, 'отправлено')) строка.отправлено++;
  if (есть(запись, 'скопировано')) строка.скопировано++;
  if (есть(запись, 'вход')) строка.другСел++;
  if (есть(запись, 'старт')) строка.партияНачата++;
  if (запись.события.some(function (с) { return с.что === 'итог' && с.доиграна === true; })) строка.доиграли++;
  if (есть(запись, 'комнатаПотеряна')) строка.сгорело++;
}

/**
 * Сводка по приглашениям за последние «дней» дней (не число или ≤ 0 —
 * за всё, что хранится). Только числа: ни номеров игроков, ни номеров
 * приглашений, ни кодов столов — её можно показывать наружу.
 *
 * Считаются записи, где человек что-то сделал (былоДействие): номер,
 * выданный заранее при показе кода стола, приглашением не был. Тестовые
 * (тест: true) не считаются вовсе. Каждая цифра — число ЗАПИСЕЙ с таким
 * событием, а не самих событий: повторный «вход» того же друга или реванш
 * цифру не раздувают.
 */
function сводка(дней) {
  загрузить();
  const окно = Number(дней) > 0 ? Number(дней) * СУТКИ : Infinity;
  const от = Date.now() - окно;
  const итого = пустаяСтрока();
  итого.отказы = { 'идёт': 0, 'заполнена': 0, 'закрыта': 0, 'нет': 0 };
  итого.поИграм = {};
  for (const запись of записи.values()) {
    if (запись.тест === true || запись.создано < от || !былоДействие(запись)) continue;
    прибавитьЗапись(итого, запись);
    const игра = запись.игра || 'неизвестно';
    if (!Object.prototype.hasOwnProperty.call(итого.поИграм, игра)) итого.поИграм[игра] = пустаяСтрока();
    прибавитьЗапись(итого.поИграм[игра], запись);
    /* Отказы считаем по причинам и по событиям: в записи их не больше
       десяти, один друг с одной причиной — один раз (см. отметитьОтказВхода). */
    for (const причина of ПРИЧИНЫ_ОТКАЗА) {
      итого.отказы[причина] += запись.события.filter(function (с) {
        return с.что === ОТКАЗ_ВХОДА && с.причина === причина;
      }).length;
    }
  }
  return итого;
}

/** Забыть всё (проверкам — начинать с чистого листа). */
