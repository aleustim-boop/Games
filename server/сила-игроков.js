'use strict';

/* =====================================================================
   СИЛА ИГРОКА — вторая мера, рядом с накопительными очками.

   ЧЕМ ОТЛИЧАЕТСЯ ОТ РЕЙТИНГА В server/рейтинг.js. Там копятся очки:
   сыграл больше — набрал больше, и это честно отвечает на вопрос
   «кто у нас самый деятельный». Здесь отвечаем на другой вопрос —
   «кто играет сильнее». Владелец попросил обе меры и вторую описал
   словами: «отдельно нужен рейтинг игры с живым игроком, там всё
   зависеть должно от уровня игрока, против которого ты играешь».

   Поэтому сила устроена наоборот накопительным очкам:
     — обыграл сильного          — заметно вырос;
     — обыграл заведомо слабого  — почти не вырос;
     — проиграл слабому          — упал;
     — просто много играл        — не изменилось ничего.

   С БОТАМИ СИЛА НЕ СЧИТАЕТСЯ ВОВСЕ. Владелец просил меру для игры
   с живыми людьми, и это же разом убирает целый способ накрутки:
   бот всегда под рукой и играть не откажется. Боты за столом просто
   пропускаются, будто их там нет.

   ЧТО ЗА СИСТЕМА И ПОЧЕМУ ИМЕННО ОНА — Глико-1.

   Эло (классика, одна формула) даёт одно число и молчит о том,
   насколько этому числу можно верить. Нам это молчание не подходит:
   владелец прямо просил, чтобы рядом было видно, много ли партий за
   числом стоит. В Глико такое число есть — «неуверенность» (в книгах
   RD, rating deviation). Оно решает сразу три наши задачи само собой:

     — новичок двигается большими шагами и быстро находит своё место;
     — у того, кто наигран, рейтинг двигается мелко и не скачет;
     — после долгого отсутствия неуверенность отрастает, и рейтинг
       снова начинает двигаться живее — человек мог измениться.

   Глико-2 (следующая версия, с третьим числом — «изменчивостью») мы
   НЕ берём нарочно. Третье число надёжно считается на сотнях партий
   одного человека. У нас круг друзей: оно будет шуметь, а не помогать,
   и объяснить его игроку нечем.

   ЧИСЛА, И ОТКУДА ОНИ ВЗЯЛИСЬ

   Старт 1500 — просто середина шкалы, как принято.
   Неуверенность на старте 250, потолок тоже 250, дно 50.
   (В книгах старт 350. Мы взяли меньше: у нас не улица, а круг друзей,
   играющих в ту же игру, — совсем незнакомым новичок не является.
   При 350 первая же партия двигала бы силу на 175 очков, а это больше,
   чем весь разумный размах в дураке.)

   ВЕС ПАРТИИ ПО ИГРАМ — главное отличие дурака от шашек.

   В дураке многое решают карты, а не голова. Это замерено, а не взято
   на глаз: `node tests/замер-уровней.js дуэль сложный лёгкий 400`
   (800 партий) дал 63,3 очка из 100 — столько набирает сложный бот
   против лёгкого, то есть при разнице в ДВА уровня силы. В переводе на
   шкалу Эло такой разрыв стоит всего около 95 очков, тогда как в
   шашках и шахматах такая же разница в умении — это 400 и больше.
   Шкала дурака вчетверо уже: одна партия там говорит о силе гораздо
   меньше.

   Отсюда вес партии: в шашках 1, в дураке 0,3. Вес уменьшает И шаг
   рейтинга, И прирост уверенности разом — иначе рейтинг называл бы
   себя «уверенным», не имея на то оснований.

   Полная поправка была бы около 0,06, но тогда до уверенного рейтинга
   пришлось бы играть 200 партий — в кругу друзей это «никогда».
   Взяли 0,3, и вот что из этого считается:

     шашки: уверенный рейтинг примерно после 11 партий,
            устоявшийся двигается на 7–13 очков за партию;
     дурак: уверенный рейтинг примерно после 37 партий,
            устоявшийся двигается на 2–4 очка за партию.

   ЗА СТОЛОМ БЫВАЕТ ОТ ДВУХ ДО ШЕСТИ. Партию раскладываем на пары
   «победитель — проигравший» и считаем их одним пересчётом (Глико это
   умеет: партия — это «период» с несколькими соперниками). Пары
   «оба выиграли» не считаем: в дураке «я не дурак» — общий итог
   пятерых, и кто из них сильнее, партия не сказала. Вес каждой пары
   1/(людей за столом − 1), чтобы партия вшестером весила столько же,
   сколько партия вдвоём, а не впятеро больше.

   ИГРА ПАРАМИ считается, но вполовину: половину результата в парах
   делает напарник, и приписывать её себе нечестно. Итого парная партия
   весит треть обычной. Не считать её вовсе было бы хуже — владелец
   играет парами часто, и его сила просто не росла бы.

   НАКРУТКА ВДВОЁМ. Двое сговорившихся могут «сдавать» друг другу
   победы. Против этого четыре слоя, и первый — главный:

     1) сила ноль-суммна: сколько один потерял, столько другой взял.
        Сдали победу по очереди — оба вернулись, откуда начали.
        Гонять партии по кругу бессмысленно по самому устройству;
     2) убывающая отдача за сутки: вторая партия с тем же человеком
        за день весит 1/2, третья 1/3, десятая 1/10. Десять партий за
        вечер дают вес примерно трёх. Скидка одна на пару и действует
        в обе стороны, поэтому «дешёвых поражений» не появляется;
     3) побеждать заведомо слабого почти бесплатно — это свойство самой
        формулы, приписывать ничего не нужно;
     4) в таблицу силы попадают только с уверенным рейтингом: одна
        везучая победа наверх не поднимает.

   ЧТО ХРАНИМ. Номер игрока в Telegram, имя, которым он назвался за
   столом, силу, неуверенность, число партий и день последней игры.
   Отдельно — счётчик партий на пару людей за ТЕКУЩИЕ сутки (нужен
   убывающей отдаче); назавтра он выбрасывается. Ни карт, ни кодов
   комнат, ни истории «кто кого обыграл» за прошлые дни.

   НАРУЖУ НОМЕР НЕ УХОДИТ НИКОГДА. Ответ собирается вручную, поле за
   полем (см. «строка» и «срезДляИгрока»): взять готовую запись целиком
   нельзя — вместе с ней уехал бы номер.
   ===================================================================== */

