/** Прочитать файл. Нет файла или он испорчен — начинаем с чистого листа. */
function загрузить() {
  ужеЗагрузили = true;
  let прочитанное = null;
  try {
    прочитанное = JSON.parse(fs.readFileSync(файл(), 'utf8'));
  } catch (сбой) {
    return;             // файла нет или он испорчен — это не беда
  }
  if (!прочитанное) return;

  const сегодня = ключДня();

  if (Array.isArray(прочитанное.игроки)) {
    for (const запись of прочитанное.игроки) {
      if (!запись || !этоНомерИгрока(запись.номер)) continue;
      const свежая = пустаяЗапись(запись.номер);
      свежая.имя = приличноеИмя(запись.имя);
      свежая.сила = Number(запись.сила) || СТАРТ_СИЛЫ;
      свежая.неуверенность = зажатьНеуверенность(Number(запись.неуверенность)
                                                 || СТАРТ_НЕУВЕРЕННОСТИ);
      свежая.партий = Number(запись.партий) || 0;
      свежая.побед = Number(запись.побед) || 0;
      свежая.поражений = Number(запись.поражений) || 0;
      свежая.ничьих = Number(запись.ничьих) || 0;
      свежая.последняяИгра = typeof запись.последняяИгра === 'string'
        ? запись.последняяИгра : '';
      свежая.последняяПартия = запись.последняяПартия || null;
      таблицаИгры(запись.игра).set(запись.номер, свежая);
    }
  }

  /* Встречи за день читаем только сегодняшние: вчерашние скидки сегодня
     не действуют, и хранить их незачем. */
  if (Array.isArray(прочитанное.встречи)) {
    for (const встреча of прочитанное.встречи) {
      if (!встреча || встреча.день !== сегодня) continue;
      if (typeof встреча.ключ !== 'string') continue;
      встречиИгры(встреча.игра).set(встреча.ключ, {
        день: сегодня,
        сколько: Number(встреча.сколько) || 0
      });
    }
  }

  прибраться();
}

/** Сложить память в файл. Молча: беда с диском не повод ронять партии. */
function записатьСейчас() {
  естьЧтоЗаписать = false;
  const игроки = [];
  for (const [игра, таблица] of таблицы) {
    for (const запись of таблица.values()) {
      игроки.push({
        игра: игра,
        номер: запись.номер,
        имя: запись.имя,
        сила: запись.сила,
        неуверенность: запись.неуверенность,
        партий: запись.партий,
        побед: запись.побед,
        поражений: запись.поражений,
        ничьих: запись.ничьих,
        последняяИгра: запись.последняяИгра,
        последняяПартия: запись.последняяПартия
      });
    }
  }
  const встречи = [];
  const сегодня = ключДня();
  for (const [игра, список] of встречиЗаДень) {
    for (const [ключ, счёт] of список) {
      if (счёт.день !== сегодня) continue;
      встречи.push({ игра: игра, ключ: ключ, день: счёт.день, сколько: счёт.сколько });
    }
  }
  try {
    fs.mkdirSync(гдеДанные.папка(), { recursive: true });
    // Во временный файл и переименование: обрывка на диске не бывает.
    fs.writeFileSync(файлПокаПишем(),
                     JSON.stringify({ игроки: игроки, встречи: встречи }), 'utf8');
    fs.renameSync(файлПокаПишем(), файл());
  } catch (сбой) {
    /* Не записалось — память останется до следующей попытки. */
  }
}

/** Пометить, что память изменилась. Настоящая запись — чуть погодя. */
function записатьПогодя() {
  if (!записьРазрешена) return;
  естьЧтоЗаписать = true;
  if (таймерЗаписи !== null) return;
  таймерЗаписи = setTimeout(function () {
    таймерЗаписи = null;
    if (естьЧтоЗаписать) записатьСейчас();
  }, ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ);
  if (таймерЗаписи.unref) таймерЗаписи.unref();
}

/** Записать прямо сейчас (нужно при остановке сервера). */
function дописать() {
  if (таймерЗаписи !== null) {
    clearTimeout(таймерЗаписи);
    таймерЗаписи = null;
  }
  if (естьЧтоЗаписать) записатьСейчас();
}

/** Забыть тех, кто давно не играл, и вчерашние встречи. */
function прибраться() {
  const край = new Date();
  край.setDate(край.getDate() - ХРАНИМ_ДНЕЙ);
  const самыйСтарый = ключДня(край.getTime());
  for (const таблица of таблицы.values()) {
    for (const [номер, запись] of таблица) {
      if (запись.последняяИгра && запись.последняяИгра < самыйСтарый) {
        таблица.delete(номер);
      }
    }
  }
  const сегодня = ключДня();
  for (const список of встречиЗаДень.values()) {
    for (const [ключ, счёт] of список) {
      if (счёт.день !== сегодня) список.delete(ключ);
    }
  }
}

/* ---------------------------------------------------------------------
   Математика Глико. Три коротких формулы, дальше — только счёт.
   --------------------------------------------------------------------- */

/** Не даём неуверенности выйти за границы. */
function зажатьНеуверенность(значение) {
  if (!Number.isFinite(значение)) return СТАРТ_НЕУВЕРЕННОСТИ;
  return Math.min(ПОТОЛОК_НЕУВЕРЕННОСТИ, Math.max(ДНО_НЕУВЕРЕННОСТИ, значение));
}

/**
 * Насколько соперник «размыт»: чем меньше о нём известно, тем меньше
 * его результат влияет на чужую силу. Это и есть g(RD) из Глико.
 */
function размытость(неуверенность) {
  return 1 / Math.sqrt(1 + 3 * q * q * неуверенность * неуверенность
                           / (Math.PI * Math.PI));
}

/**
 * Ожидаемый счёт: с какой долей вероятности игрок силы «моя» обыграет
 * соперника силы «его». 0,5 — равные, ближе к 1 — заведомо сильнее.
 */
function ожидание(моя, его, неуверенностьЕго) {
  return 1 / (1 + Math.pow(10, -размытость(неуверенностьЕго) * (моя - его) / 400));
}

/**
 * Неуверенность на сегодня: за дни без игры она отрастает.
 * В памяти хранится значение на день последней партии, а не «на сейчас», —
 * иначе простой просмотр таблицы менял бы данные.
 */
function неуверенностьНаСегодня(запись, сегодня) {
  if (!запись.последняяИгра) return зажатьНеуверенность(запись.неуверенность);
  const дней = днейМежду(запись.последняяИгра, сегодня || ключДня());
  if (дней <= 0) return зажатьНеуверенность(запись.неуверенность);
  const было = запись.неуверенность;
  return зажатьНеуверенность(Math.sqrt(было * было + ОТРАСТАНИЕ_ЗА_ДЕНЬ * дней));
}

/**
 * Пересчёт по Глико за одну партию.
 *
 * Приходит список сравнений: с кем играли, каков был итог (1 — победа,
 * 0,5 — ничья, 0 — поражение) и какой у сравнения вес. Вес — это
 * «доля партии»: 0,3 значит, что партия говорит о силе втрое меньше
 * обычного. Вес уменьшает и шаг рейтинга, и прирост уверенности разом —
 * иначе рейтинг называл бы себя точным без оснований.
 */
function пересчитать(силаМоя, неуверенностьМоя, сравнения) {
  let сдвиг = 0;      // куда и насколько тянет результат
  let сведения = 0;   // сколько нового мы узнали о силе

  for (const с of сравнения) {
    const g = размытость(с.неуверенностьСоперника);
    const ожидаемое = ожидание(силаМоя, с.силаСоперника, с.неуверенностьСоперника);
    сдвиг += с.вес * g * (с.итог - ожидаемое);
    сведения += с.вес * q * q * g * g * ожидаемое * (1 - ожидаемое);
  }

  if (сведения <= 0) {
    return { сила: силаМоя, неуверенность: неуверенностьМоя, изменение: 0 };
  }

  const знаменатель = 1 / (неуверенностьМоя * неуверенностьМоя) + сведения;
  const изменение = q * сдвиг / знаменатель;
  return {
    сила: силаМоя + изменение,
    неуверенность: зажатьНеуверенность(Math.sqrt(1 / знаменатель)),
    изменение: изменение
  };
}

/* ---------------------------------------------------------------------
   Разбор застолья: кого с кем сравнивать
   --------------------------------------------------------------------- */

/** Ключ пары людей: всегда меньший номер первым, чтобы был один на двоих. */
function ключПары(номерА, номерБ) {
  return номерА < номерБ ? номерА + ':' + номерБ : номерБ + ':' + номерА;
}

/**
 * Скидка за повтор: которая по счёту это партия с тем же человеком
 * сегодня. Первая — полный вес, вторая — половина, третья — треть.
 * Считаем, не увеличивая счётчик: увеличим один раз, когда партия
 * действительно зачтена.
 */
function скидкаЗаПовтор(игра, номерА, номерБ, сегодня) {
  const список = встречиИгры(игра);
  const счёт = список.get(ключПары(номерА, номерБ));
  const былоСегодня = (счёт && счёт.день === сегодня) ? счёт.сколько : 0;
  return 1 / (былоСегодня + 1);
}

/** Отметить, что эта пара сегодня сыграла ещё одну партию. */
function отметитьВстречу(игра, номерА, номерБ, сегодня) {
  const список = встречиИгры(игра);
  const ключ = ключПары(номерА, номерБ);
  const счёт = список.get(ключ);
  if (счёт && счёт.день === сегодня) счёт.сколько++;
  else список.set(ключ, { день: сегодня, сколько: 1 });
}

/**
 * Игра парами или нет.
 *
 * ВРЕМЕННАЯ ПРИМЕТА, и её надо будет убрать. Комнаты пока не передают
 * сюда признак «парами», поэтому парную партию узнаём по форме стола:
 * четверо и ровно двое проигравших (в обычном дураке дурак один).
 * Примета верна, пока все четверо — люди; если двое из четверых боты,
 * она молчит. Штаб решил добавить поле «парами» в застолье со стороны
 * server/комнаты.js — как только оно появится, эта функция начнёт
 * читать его и гадать перестанет (код для этого уже написан ниже).
 */
function партияПарами(застолье) {
  for (const игрок of застолье) {
    if (игрок && игрок.парами !== undefined) return игрок.парами === true;
  }
  const проигравших = застолье.filter(function (и) {
    return и && !и.победил && !и.ничья;
  }).length;
  return застолье.length === 4 && проигравших === 2;
}

/* ---------------------------------------------------------------------
   Учёт партии
   --------------------------------------------------------------------- */

/**
 * Записать итог партии в силу игроков.
 *
 * Приходит то же застолье, что и накопительному рейтингу:
 * { номер, имя, этоБот, уровень, победил, ничья }. Боты и все, у кого
 * нет номера Telegram, пропускаются: сила — мера игры с живыми людьми.
 *
 * Все пересчёты делаются от ОДНОГО снимка «как было до партии»: иначе
 * первый посчитанный игрок влиял бы на второго, и результат зависел бы
 * от порядка мест за столом.
 */
function учесть(игра, застольем) {
  if (!ужеЗагрузили) загрузить();
  if (!Array.isArray(застольем)) return;

  const сегодня = ключДня();

  // 1. Оставляем только живых людей, которых можем опознать.
  const люди = [];
  for (const игрок of застольем) {
    if (!игрок || игрок.этоБот || !этоНомерИгрока(игрок.номер)) continue;
    if (люди.some(function (у) { return у.номер === игрок.номер; })) continue;
    люди.push(игрок);
  }
  if (люди.length < 2) return;      // сравнивать не с кем

  const парами = партияПарами(застольем);
  const вес = весИгры(игра)
            * (1 / (люди.length - 1))
            * (парами ? ВЕС_ПАРНОЙ_ИГРЫ : 1);

  /* 2. Снимок «как было»: сила и отросшая за простой неуверенность.
     Заодно сразу записываем имена — ВСЕМ и до расчётов. Иначе рассказ
     о партии для первого игрока составлялся бы раньше, чем соперник
     получил своё имя, и человек читал бы «Обыграли: Игрок, Игрок». */
  const было = new Map();
  for (const человек of люди) {
    const запись = записьИгрока(игра, человек.номер);
    if (приличноеИмя(человек.имя)) запись.имя = приличноеИмя(человек.имя);
    было.set(человек.номер, {
      сила: запись.сила,
      неуверенность: неуверенностьНаСегодня(запись, сегодня)
    });
  }

  // 3. Собираем сравнения: только там, где партия и вправду сравнила.
  const сравнения = new Map();
  for (const человек of люди) сравнения.set(человек.номер, []);
  const встретились = [];

  for (let а = 0; а < люди.length; а++) {
    for (let б = а + 1; б < люди.length; б++) {
      const первый = люди[а];
      const второй = люди[б];
      const итог = итогПары(первый, второй, люди.length);
      if (итог === null) continue;      // партия про эту пару ничего не сказала

      const скидка = скидкаЗаПовтор(игра, первый.номер, второй.номер, сегодня);
      const весПары = вес * скидка;
      const данныеПервого = было.get(первый.номер);
      const данныеВторого = было.get(второй.номер);

      сравнения.get(первый.номер).push({
        номерСоперника: второй.номер,
        силаСоперника: данныеВторого.сила,
        неуверенностьСоперника: данныеВторого.неуверенность,
        итог: итог,
        вес: весПары
      });
      сравнения.get(второй.номер).push({
        номерСоперника: первый.номер,
        силаСоперника: данныеПервого.сила,
        неуверенностьСоперника: данныеПервого.неуверенность,
        итог: 1 - итог,
        вес: весПары
      });
      встретились.push([первый.номер, второй.номер]);
    }
  }

  if (встретились.length === 0) return;   // например ничья за большим столом

  // 4. Пересчитываем каждого от снимка и складываем словами, что вышло.
  let менялось = false;
  for (const человек of люди) {
    const мои = сравнения.get(человек.номер);
    if (!мои || мои.length === 0) continue;

    const запись = записьИгрока(игра, человек.номер);
    const старт = было.get(человек.номер);
    const новое = пересчитать(старт.сила, старт.неуверенность, мои);

    запись.сила = новое.сила;
    запись.неуверенность = новое.неуверенность;
    запись.партий++;
    запись.последняяИгра = сегодня;
    if (человек.ничья) запись.ничьих++;
    else if (человек.победил) запись.побед++;
    else запись.поражений++;

    запись.последняяПартия = итогПартииСловами(запись, старт, новое, мои, игра, парами);
    менялось = true;
  }

  // 5. Отмечаем встречи — после расчёта, чтобы скидка была одна на партию.
  for (const пара of встретились) отметитьВстречу(игра, пара[0], пара[1], сегодня);

  if (менялось) записатьПогодя();
}

/**
 * Что партия сказала об этой паре: 1 — первый выиграл, 0 — проиграл,
 * 0,5 — ничья, null — не сказала ничего.
 *
 * «Оба выиграли» за большим столом — это не сравнение: в дураке «я не
 * дурак» — общий итог всех, кроме одного, и кто из них сильнее, партия
 * не показала. Ничья вдвоём — сравнение настоящее: двое сыграли ровно.
 * Ничья за большим столом силу не двигает по той же причине, что и
 * «оба выиграли»: сравнивать некого.
 */
function итогПары(первый, второй, людейЗаСтолом) {
  if (первый.ничья || второй.ничья) {
    return людейЗаСтолом === 2 ? 0.5 : null;
  }
  if (первый.победил && !второй.победил) return 1;
  if (!первый.победил && второй.победил) return 0;
  if (!первый.победил && !второй.победил) {
    /* Оба проиграли — так бывает у пары в парной игре. Между собой они
       не соперники, сравнивать их нечем. */
    return null;
  }
  return null;
}

/* ---------------------------------------------------------------------
   Слова для игрока. Не украшение: человек, у которого сила упала,
   должен прочитать почему, а не догадываться.
   --------------------------------------------------------------------- */

/** Округление до целого очка — игроку показываем целые числа. */
function целое(число) {
  return Math.round(число);
}

/** «+12» или «−7» (минус настоящий, а не дефис). */
function соЗнаком(число) {
  const целоеЧисло = целое(число);
  if (целоеЧисло > 0) return '+' + целоеЧисло;
  if (целоеЧисло < 0) return '−' + Math.abs(целоеЧисло);
  return '0';
}

/* Меньше этой разницы в силе игроков считаем равными. Полсотни очков —
   это меньше, чем сила гуляет от везения, и называть такого соперника
   «слабее вас» было бы неправдой. */
const РАЗНИЦА_ЗАМЕТНА = 50;

/** Кто был сильнее перед партией: «сильнее», «слабее» или «вровень». */
function ктоБылСильнее(мояСила, силаСоперника) {
  if (силаСоперника - мояСила >= РАЗНИЦА_ЗАМЕТНА) return 'сильнее';
  if (мояСила - силаСоперника >= РАЗНИЦА_ЗАМЕТНА) return 'слабее';
  return 'вровень';
}

/** Имя соперника для показа; безымянного зовём «Игрок». */
function имяСоперника(игра, номер) {
  const запись = таблицаИгры(игра).get(номер);
  return (запись && запись.имя) ? запись.имя : 'Игрок';
}

/**
 * Собрать рассказ о последней партии: на сколько сдвинулась сила,
 * с кем играли и почему вышло именно столько.
 */
function итогПартииСловами(запись, старт, новое, сравнения, игра, парами) {
  const обыгранные = [];
  const обыгравшие = [];
  const ничьи = [];
  const соперники = [];

  for (const с of сравнения) {
    const имя = имяСоперника(игра, с.номерСоперника);
    соперники.push({
      имя: имя,
      сила: целое(с.силаСоперника),
      сравнение: ктоБылСильнее(старт.сила, с.силаСоперника)
    });
    if (с.итог === 1) обыгранные.push(имя);
    else if (с.итог === 0) обыгравшие.push(имя);
    else ничьи.push(имя);
  }

  const части = [];

  if (обыгранные.length) части.push('Обыграли: ' + обыгранные.join(', ') + '.');
  if (обыгравшие.length) части.push('Проиграли: ' + обыгравшие.join(', ') + '.');
  /* «Ничья: Мария», а не «Ничья с Мария». Имена не склоняем нигде и
     никогда: они бывают любые, включая иностранные и выдуманные, и
     правильно склонить их нельзя. Обходим падеж двоеточием — тот же
     приём, что и у «Обыграли:» выше. */
  if (ничьи.length) части.push('Ничья: ' + ничьи.join(', ') + '.');

  /* Почему вышло именно столько — самое важное для того, кто упал.
     Смотрим на самого показательного соперника: при победе — на самого
     сильного из обыгранных, при поражении — на самого слабого из тех,
     кто обошёл. Именно он и объясняет размер числа. */
  const каков = function (имена, ищемСильнейшего) {
    let лучший = null;
    for (const с of соперники) {
      if (имена.indexOf(с.имя) === -1) continue;
      if (лучший === null) { лучший = с; continue; }
      if (ищемСильнейшего ? с.сила > лучший.сила : с.сила < лучший.сила) лучший = с;
    }
    return лучший ? лучший.сравнение : 'вровень';
  };

  if (обыгранные.length && !обыгравшие.length) {
    const кто = каков(обыгранные, true);
    if (кто === 'сильнее') части.push('Соперник играл сильнее вас — за такую победу дают больше.');
    else if (кто === 'слабее') части.push('Соперник играл слабее вас — за такую победу дают немного.');
    else части.push('Соперник был вам примерно равен — прибавка обычная.');
  } else if (обыгравшие.length && !обыгранные.length) {
    const кто = каков(обыгравшие, false);
    if (кто === 'сильнее') части.push('Соперник играл сильнее вас — потеря небольшая, проиграть сильному не стыдно.');
    else if (кто === 'слабее') части.push('Соперник играл слабее вас — поэтому потеря заметная.');
    else части.push('Соперник был вам примерно равен — потеря обычная.');
  } else if (обыгранные.length && обыгравшие.length) {
    части.push('За столом были и те, кого вы обошли, и те, кто обошёл вас, — '
               + 'сила посчитана по каждому.');
  }

  if (парами) части.push('Игра парами считается вполовину: половину сделал напарник.');

  if (новое.неуверенность > ПОРОГ_УВЕРЕННОСТИ) {
    части.push('Рейтинг ещё приблизительный, поэтому двигается большими шагами.');
  }

  return {
    когда: запись.последняяИгра,
    было: целое(старт.сила),
    стало: целое(новое.сила),
    изменение: целое(новое.изменение),
    изменениеСловами: соЗнаком(новое.изменение),
    соперники: соперники,
    словами: части.join(' ')
  };
}

/* ---------------------------------------------------------------------
   Прогноз: сколько получу или потеряю
   --------------------------------------------------------------------- */

/**
 * Прогноз для будущей партии: на сколько изменится сила при победе,
 * при поражении и при ничьей.
 *
 * Нужен, чтобы падение не выглядело наказанием без объяснения: человек
 * видит цену партии заранее. Соперники называются номерами Telegram —
 * функцию зовёт сервер, у которого они есть; наружу номера не уходят.
 */
function прогноз(игра, мойНомер, номераСоперников, настройки) {
  if (!ужеЗагрузили) загрузить();
  if (!этоНомерИгрока(мойНомер) || !Array.isArray(номераСоперников)) return null;

  const сегодня = ключДня();
  const соперники = номераСоперников.filter(function (номер) {
    return этоНомерИгрока(номер) && номер !== мойНомер;
  });
  if (соперники.length === 0) return null;

  const парами = !!(настройки && настройки.парами);
  const людей = соперники.length + 1;
  const вес = весИгры(игра) * (1 / (людей - 1)) * (парами ? ВЕС_ПАРНОЙ_ИГРЫ : 1);

  const мояЗапись = таблицаИгры(игра).get(мойНомер) || пустаяЗапись(мойНомер);
  const мояСила = мояЗапись.сила;
  const мояНеуверенность = неуверенностьНаСегодня(мояЗапись, сегодня);

  /* В прогнозе считаем простой случай: со всеми соперниками результат
     одинаковый. За большим столом так и бывает — либо ты дурак, либо нет. */
  const собрать = function (итог) {
    const список = [];
    for (const номер of соперники) {
      const запись = таблицаИгры(игра).get(номер) || пустаяЗапись(номер);
      список.push({
        силаСоперника: запись.сила,
        неуверенностьСоперника: неуверенностьНаСегодня(запись, сегодня),
        итог: итог,
        вес: вес * скидкаЗаПовтор(игра, мойНомер, номер, сегодня)
      });
    }
    return пересчитать(мояСила, мояНеуверенность, список).изменение;
  };

  const заПобеду = собрать(1);
  const заПоражение = собрать(0);
  const заНичью = собрать(0.5);

  /* Ноль в прогнозе бывает по делу: обыграть заведомо слабого почти
     ничего не даёт, а проиграть заведомо сильному почти ничего не стоит.
     Говорим об этом словами, а не показываем «+0» — иначе выглядит
     поломкой. */
  const проПобеду = целое(заПобеду) === 0
    ? 'выиграете — сила почти не изменится'
    : 'выиграете — ' + соЗнаком(заПобеду);
  const проПоражение = целое(заПоражение) === 0
    ? 'проиграете — почти ничего не потеряете'
    : 'проиграете — ' + соЗнаком(заПоражение);

  return {
    сила: целое(мояСила),
    заПобеду: целое(заПобеду),
    заПоражение: целое(заПоражение),
    заНичью: целое(заНичью),
    словами: 'Если ' + проПобеду + '; ' + проПоражение + '.'
  };
}

/* ---------------------------------------------------------------------
   Что видит игрок
   --------------------------------------------------------------------- */

/** Уверенный ли это рейтинг — то есть можно ли ему верить. */
function надёжно(неуверенность) {
  return неуверенность <= ПОРОГ_УВЕРЕННОСТИ;
}

/**
 * Сколько ещё партий примерно нужно до уверенного рейтинга.
 * Считаем для игры один на один с наигранным соперником: за большим
 * столом партия весит меньше, и партий понадобится больше.
 */
function сколькоЕщёПартий(игра, неуверенность) {
  if (надёжно(неуверенность)) return 0;
  const g = размытость(ПОРОГ_УВЕРЕННОСТИ);
  const заПартию = весИгры(игра) * q * q * g * g * 0.25;
  const нужно = 1 / (ПОРОГ_УВЕРЕННОСТИ * ПОРОГ_УВЕРЕННОСТИ)
              - 1 / (неуверенность * неуверенность);
  if (заПартию <= 0 || нужно <= 0) return 0;
  return Math.max(1, Math.ceil(нужно / заПартию));
}

/**
 * Одна строка таблицы наружу. Собирается вручную, поле за полем:
 * номер Telegram остаётся здесь и наружу не уходит никогда.
 */
function строка(запись, место, этоЯ, сегодня) {
  const неуверенность = неуверенностьНаСегодня(запись, сегодня);
  return {
    место: место,
    имя: запись.имя || 'Игрок',
    сила: целое(запись.сила),
    партий: запись.партий,
    надёжно: надёжно(неуверенность),
    этоЯ: этоЯ === true
  };
}

/**
 * Вся таблица игры по порядку: сильнее — выше.
 * В список попадают только уверенные рейтинги: иначе новичок с одной
 * везучей победой висел бы наверху, а это и обидно, и неправда.
 */
function порядок(игра, сегодня) {
  if (!ужеЗагрузили) загрузить();
  const все = [];
  for (const запись of таблицаИгры(игра).values()) {
    if (!надёжно(неуверенностьНаСегодня(запись, сегодня))) continue;
    все.push(запись);
  }
  все.sort(function (а, б) {
    if (б.сила !== а.сила) return б.сила - а.сила;
    if (б.партий !== а.партий) return б.партий - а.партий;
    // Совсем поровну — раньше тот, кто играл недавно: таблица живее.
    return String(б.последняяИгра).localeCompare(String(а.последняяИгра));
  });
  return все;
}

/** Пояснение к своему числу — человеческими словами, а не отчётом. */
function поясненияКСиле(игра, запись, неуверенность) {
  if (!запись || запись.партий === 0) {
    return 'Сила считается по партиям с живыми игроками. Сыграйте первую — '
         + 'и число появится.';
  }
  if (!надёжно(неуверенность)) {
    const ещё = сколькоЕщёПартий(игра, неуверенность);
    /* Отдельный случай — вернувшийся после перерыва. Иначе человек с
       сорока партиями читает «рейтинг приблизительный» и не понимает,
       за что: он-то наигран. Узнаём перерыв по тому, что неуверенность
       отросла со времени последней партии. */
    const послеПерерыва = неуверенность > запись.неуверенность + 5;
    const начало = послеПерерыва
      ? 'Вы давно не играли, и рейтинг снова стал приблизительным — за это время '
        + 'вы могли играть и лучше, и хуже. За ним ' + запись.партий + ' '
        + партийСловом(запись.партий) + '.'
      : 'Рейтинг ещё приблизительный: за ним ' + запись.партий + ' '
        + партийСловом(запись.партий) + '.';
    return начало + ' Сыграйте ещё примерно ' + ещё + ' ' + партийСловом(ещё)
         + ' с живыми игроками — и он снова станет точным.';
  }
  return 'Рейтинг уверенный: за ним ' + запись.партий + ' '
       + партийСловом(запись.партий) + ' с живыми игроками, а разброс не больше '
       + '±' + ПОРОГ_УВЕРЕННОСТИ + ' — столько мы и считаем точным. '
       + '1500 — средний уровень: выше — вы играете сильнее большинства.';
}

/**
 * Слово в нужном числе: словоПоЧислу(3, 'партия', 'партии', 'партий').
 * Нужно, чтобы игра не писала «349 победа» и «1 партий».
 */
function словоПоЧислу(сколько, одна, две, много) {
  const число = Math.abs(Math.round(сколько));
  const последняя = число % 10;
  const сотня = число % 100;
  if (сотня >= 11 && сотня <= 14) return много;
  if (последняя === 1) return одна;
  if (последняя >= 2 && последняя <= 4) return две;
  return много;
}

/** «партия», «партии», «партий» — чтобы фраза читалась по-русски. */
function партийСловом(сколько) {
  return словоПоЧислу(сколько, 'партия', 'партии', 'партий');
}

/**
 * Готовая строка счёта: «Сыграно 601 партия: 349 побед, 1 ничья, 251 поражение».
 *
 * Собирается здесь, а не на экране, нарочно. На снимке экран показал
 * «601 партия: 349 побед, 251 поражение» — а это 600, и человек, умеющий
 * складывать, сразу видит недостачу: пропала ничья. Числа и их сумма
 * должны рождаться в одном месте, тогда они не разойдутся.
 */
function счётСловами(запись) {
  if (!запись || запись.партий === 0) return '';
  const куски = [];
  куски.push(запись.побед + ' ' + словоПоЧислу(запись.побед, 'победа', 'победы', 'побед'));
  if (запись.ничьих > 0) {
    куски.push(запись.ничьих + ' ' + словоПоЧислу(запись.ничьих, 'ничья', 'ничьи', 'ничьих'));
  }
  куски.push(запись.поражений + ' '
             + словоПоЧислу(запись.поражений, 'поражение', 'поражения', 'поражений'));
  return 'Сыграно ' + запись.партий + ' ' + партийСловом(запись.партий)
       + ': ' + куски.join(', ') + '.';
}

/**
 * Срез таблицы силы для этого игрока: своя сила со всеми пояснениями,
 * верхушка и соседи. Номер приходит уже проверенным — подпись Telegram
 * этот файл не видит.
 */
function срезДляИгрока(игра, номер) {
  if (!ужеЗагрузили) загрузить();
  const сегодня = ключДня();
  const имя = имяИгры(игра);
  const все = порядок(имя, сегодня);
  const мояЗапись = таблицаИгры(имя).get(номер) || null;

  const верхушка = все.slice(0, ВЕРХУШКИ).map(function (запись, место) {
    return строка(запись, место + 1, запись.номер === номер, сегодня);
  });

  const моёМесто = все.findIndex(function (запись) { return запись.номер === номер; });
  const вокруг = [];
  if (моёМесто !== -1) {
    const начало = Math.max(0, моёМесто - СОСЕДЕЙ_СВЕРХУ);
    const конец = Math.min(все.length, моёМесто + СОСЕДЕЙ_СНИЗУ + 1);
    for (let место = начало; место < конец; место++) {
      вокруг.push(строка(все[место], место + 1, все[место].номер === номер, сегодня));
    }
  }

  const неуверенность = мояЗапись
    ? неуверенностьНаСегодня(мояЗапись, сегодня)
    : СТАРТ_НЕУВЕРЕННОСТИ;

  return {
    всего: все.length,
    моя: {
      есть: !!(мояЗапись && мояЗапись.партий > 0),
      значение: мояЗапись ? целое(мояЗапись.сила) : СТАРТ_СИЛЫ,
      надёжно: !!(мояЗапись && мояЗапись.партий > 0 && надёжно(неуверенность)),
      /* Разброс — насколько число может гулять. Показываем РОВНО ту же
         величину, по которой стоит порог уверенности (100), а не удвоенную.

         Раньше здесь была двойка — «почти наверняка внутри» по книжной
         мерке. И на экране выходило враньё на глазах у человека: «рейтинг
         уверенный» и рядом «±169», хотя уверенным мы называем всё до 100.
         Два числа в разных мерках рядом читаются как ошибка, даже когда
         каждое по отдельности верно. Теперь мерка одна: уверенный — это
         разброс до ±100, самый точный из возможных — ±50 (ниже система
         не опускается нарочно, иначе рейтинг застыл бы навсегда). */
      разброс: целое(неуверенность),
      партий: мояЗапись ? мояЗапись.партий : 0,
      побед: мояЗапись ? мояЗапись.побед : 0,
      /* Ничьи отдаём отдельным числом и готовой строкой «счёт»: без них
         победы с поражениями не складываются в общее число партий. */
      ничьих: мояЗапись ? мояЗапись.ничьих : 0,
      поражений: мояЗапись ? мояЗапись.поражений : 0,
      счёт: счётСловами(мояЗапись),
      место: моёМесто === -1 ? null : моёМесто + 1,
      ещёПартий: сколькоЕщёПартий(имя, неуверенность),
      пояснение: поясненияКСиле(имя, мояЗапись, неуверенность)
    },
    последняяПартия: мояЗапись ? мояЗапись.последняяПартия : null,
    верхушка: верхушка,
    вокругМеня: вокруг
  };
}

