const СТАРТ_СИЛЫ = 1500;
const СТАРТ_НЕУВЕРЕННОСТИ = 250;
const ДНО_НЕУВЕРЕННОСТИ = 50;
const ПОТОЛОК_НЕУВЕРЕННОСТИ = 250;

/* Ниже этой неуверенности рейтинг считаем уверенным: и место в таблице
   даём, и говорим игроку, что число уже настоящее. 100 — обычная граница
   в Глико, и у нас она выходит на разумное число партий (11 и 37). */
const ПОРОГ_УВЕРЕННОСТИ = 100;

/* Постоянная Глико: перевод шкалы 400 очков в натуральные логарифмы. */
const q = Math.LN10 / 400;

/* Сколько весит одна партия в каждой игре — см. замер в шапке.
   Незнакомую игру считаем осторожно, по дураку: ошибиться в меньшую
   сторону здесь безопаснее, чем разогнать чужой рейтинг. */
const ВЕС_ПАРТИИ = { дурак: 0.3, шашки: 1 };
const ВЕС_НЕЗНАКОМОЙ_ИГРЫ = 0.3;

/* Игра парами весит вполовину: половину сделал напарник. */
const ВЕС_ПАРНОЙ_ИГРЫ = 0.5;

/* Насколько отрастает неуверенность за день без игры. Подобрано так,
   чтобы с самого дна (50) она вернулась к потолку (250) примерно за год:
   после месяца тишины будет 86, после трёх — 131. Человек, пропавший на
   год, возвращается «новичком» — и это правда, он мог измениться. */
const ОТРАСТАНИЕ_ЗА_ДЕНЬ = (ПОТОЛОК_НЕУВЕРЕННОСТИ * ПОТОЛОК_НЕУВЕРЕННОСТИ
                            - ДНО_НЕУВЕРЕННОСТИ * ДНО_НЕУВЕРЕННОСТИ) / 365;

/* Сколько помним неигравшего человека — столько же, сколько
   накопительный рейтинг: полгода. */
const ХРАНИМ_ДНЕЙ = 180;

/* Сколько строк показываем. Как в накопительной таблице: верхушка
   и соседи, потому что человеку на сороковом месте первая тройка
   бесполезна. */
const ВЕРХУШКИ = 3;
const СОСЕДЕЙ_СВЕРХУ = 5;
const СОСЕДЕЙ_СНИЗУ = 5;

/* Пишем не сразу: конец партии трогает память несколько раз подряд. */
const ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ = 5000;

