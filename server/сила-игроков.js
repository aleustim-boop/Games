/* игра → (номер игрока → запись). Таблицы раздельные: сила в дураке
   ничего не говорит о силе в шашках. */
const таблицы = new Map();

/* игра → (ключ пары людей → { день, сколько }). Нужно убывающей отдаче.
   Живёт ровно сутки. */
const встречиЗаДень = new Map();

let записьРазрешена = false;
let ужеЗагрузили = false;
let таймерЗаписи = null;
let естьЧтоЗаписать = false;

/** Разрешить запись на диск (сервер с «--без-памяти» её не включает). */
function включитьЗапись() {
  записьРазрешена = true;
}

/** «2026-09-08» по местному времени. */
function ключДня(время) {
  const дата = new Date(время === undefined ? Date.now() : время);
  const месяц = String(дата.getMonth() + 1).padStart(2, '0');
  const число = String(дата.getDate()).padStart(2, '0');
  return дата.getFullYear() + '-' + месяц + '-' + число;
}

/** Сколько дней прошло от одного дня до другого. Мусор — ноль дней. */
function днейМежду(деньРаньше, деньПозже) {
  const а = Date.parse(деньРаньше + 'T00:00:00');
  const б = Date.parse(деньПозже + 'T00:00:00');
  if (!Number.isFinite(а) || !Number.isFinite(б)) return 0;
  return Math.max(0, Math.round((б - а) / 86400000));
}

/** Похоже ли это на настоящий номер игрока в Telegram. */
function этоНомерИгрока(номер) {
  return Number.isInteger(номер) && номер > 0;
}

/** Имя как строка разумной длины — или пусто. */
function приличноеИмя(имя) {
  if (typeof имя !== 'string') return '';
  const чистое = имя.trim();
  return чистое ? чистое.slice(0, 40) : '';
}

/** Название игры, с которым мы умеем работать. */
function имяИгры(игра) {
  return typeof игра === 'string' && игра ? игра : 'дурак';
}

/** Таблица этой игры; заводим по первому обращению. */
function таблицаИгры(игра) {
  const имя = имяИгры(игра);
  if (!таблицы.has(имя)) таблицы.set(имя, new Map());
  return таблицы.get(имя);
}

/** Встречи этой игры за сегодня; заводим по первому обращению. */
function встречиИгры(игра) {
  const имя = имяИгры(игра);
  if (!встречиЗаДень.has(имя)) встречиЗаДень.set(имя, new Map());
  return встречиЗаДень.get(имя);
}

/** Сколько весит одна партия в этой игре. */
function весИгры(игра) {
  const вес = ВЕС_ПАРТИИ[имяИгры(игра)];
  return вес === undefined ? ВЕС_НЕЗНАКОМОЙ_ИГРЫ : вес;
}

/** Пустая запись игрока: сила средняя, доверия к ней пока мало. */
function пустаяЗапись(номер) {
  return {
    номер: номер,
    имя: '',
    сила: СТАРТ_СИЛЫ,
    неуверенность: СТАРТ_НЕУВЕРЕННОСТИ,
    партий: 0,          // партий, которые и вправду двигали силу
    побед: 0,
    поражений: 0,
    ничьих: 0,
    последняяИгра: '',
    /* Итог последней партии — чтобы человеку было что прочитать, а не
       гадать, почему число упало. Наружу уходит целиком, номеров в нём нет. */
    последняяПартия: null
  };
}

/** Запись игрока; заводим по первой партии. */
function записьИгрока(игра, номер) {
  const таблица = таблицаИгры(игра);
  if (!таблица.has(номер)) таблица.set(номер, пустаяЗапись(номер));
  return таблица.get(номер);
}

