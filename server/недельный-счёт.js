'use strict';
// Отдельный срез уже начисленных очков. Цены партий и ограничения рейтинга не меняет.
function началоНедели(день) {
  const дата = new Date(день + 'T12:00:00Z');
  дата.setUTCDate(дата.getUTCDate() - (дата.getUTCDay() + 6) % 7);
  return дата.toISOString().slice(0, 10);
}
function прочитать(значение) {
  if (!значение || !/^\d{4}-\d{2}-\d{2}$/.test(значение.с || '')) return null;
  const число = в => Number.isSafeInteger(в) && в >= 0 ? в : 0;
  return { с: значение.с, очки: число(значение.очки), побед: число(значение.побед), партий: число(значение.партий) };
}
function добавить(запись, день, очки, победил) {
  const с = началоНедели(день);
  if (!запись.недельный || запись.недельный.с !== с) запись.недельный = { с, очки: 0, побед: 0, партий: 0 };
  запись.недельный.очки += очки;
  запись.недельный.побед += победил ? 1 : 0;
  запись.недельный.партий++;
}
function список(записи, день, этоЛичина) {
  const с = началоНедели(день);
  return Array.from(записи).filter(з => з.недельный?.с === с && з.недельный.партий > 0 && !этоЛичина(з.номер))
    .sort((а, б) => б.недельный.очки - а.недельный.очки || б.недельный.побед - а.недельный.побед || а.номер - б.номер)
    .slice(0, 10).map((з, и) => ({ место: и + 1, имя: з.имя || 'Игрок' }));
}
module.exports = { началоНедели, прочитать, добавить, список };
