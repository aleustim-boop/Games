/** Имя для письма: без управляющих знаков и длинных хвостов. */
function чистоеИмя(имя) {
  /* Режем по знакам, а не по кускам UTF-16: эмодзи занимает два куска,
     и обычный slice разрезал бы его пополам (в письме остался бы «мусор»). */
  return Array.from(String(имя || '').replace(/[\s\x00-\x1f]+/g, ' ').trim()).slice(0, ИМЯ_В_ПИСЬМЕ).join('');
}

/** «очко» / «очка» / «очков» под число. */
function словоОчко(число) {
  const остаток10 = число % 10;
  const остаток100 = число % 100;
  if (остаток10 === 1 && остаток100 !== 11) return 'очко';
  if (остаток10 >= 2 && остаток10 <= 4 && (остаток100 < 12 || остаток100 > 14)) return 'очка';
  return 'очков';
}

function строкаРейтинга(очков, язык = 'ru') {
  const число = Number(очков);
  if (язык !== 'ru') return Number.isFinite(число) && число > 0 ? (язык === 'uk' ? 'Рейтинг: +' : 'Rating: +') + число : языки.текст('Рейтинг: без изменений', язык);
  if (Number.isFinite(число) && число > 0) return 'Рейтинг: +' + число + ' ' + словоОчко(число);
  return 'Рейтинг: без изменений';
}

/** Заголовок: у дурака — «Дурак» (событие не знает, подкидной он или переводной), у остальных — название из таблицы. */
function названиеИгры(игра) {
  return игра === 'дурак' ? 'Дурак' : названия.словаИгры(игра).название;
}

/** Итог одной фразой после тире. null — исход незнаком, письма нет. */
function фразаИсхода(игра, исход, язык = 'ru') {
  if (язык !== 'ru') return ({
    победа: язык === 'uk' ? 'перемога!' : 'victory!',
    поражение: язык === 'uk' ? 'поразка.' : 'defeat.',
    ничья: язык === 'uk' ? 'нічия.' : 'draw.',
    внеСчёта: язык === 'uk' ? 'партію завершено за згодою, без очок.' : 'game ended by agreement, no points.'
  })[исход] || null;
  const дурак = игра === 'дурак';
  switch (исход) {
    case 'победа': return дурак ? 'вы не в дураках.' : 'победа!';
    case 'поражение': return дурак ? 'вы остались в дураках.' : 'поражение.';
    case 'ничья': return 'ничья.';
    case 'внеСчёта': return 'партия закончена по согласию, без очков.';
    default: return null;
  }
}

/** «Лена», «Лена и Петя», «Лена, Петя и бот», «Лена, Петя и ещё 2». */
function списокИмён(имена, язык = 'ru') {
  if (язык !== 'ru' && имена.length > 1) {
    const и = язык === 'uk' ? ' та ' : ' and ';
    return имена.length <= 3 ? имена.slice(0, -1).join(', ') + и + имена[имена.length - 1]
      : имена.slice(0, 2).join(', ') + и + (язык === 'uk' ? 'ще ' : '') + (имена.length - 2) + (язык === 'en' ? ' more' : '');
  }
  if (имена.length <= 1) return имена.join('');
  if (имена.length === 2) return имена[0] + ' и ' + имена[1];
  if (имена.length === 3) return имена[0] + ', ' + имена[1] + ' и ' + имена[2];
  return имена[0] + ', ' + имена[1] + ' и ещё ' + (имена.length - 2);
}

/** Как назвать место в письме: бот — «бот», гость без Telegram-номера —
 *  «гость», человек с номером — имя из подписи Telegram (нет подписи — «игрок»). */
function имяМеста(место, язык = 'ru') {
  if (место.этоБот) return языки.текст('бот', язык);
  const номер = Number(место.номер);
  if (!(Number.isInteger(номер) && номер > 0)) return языки.текст('гость', язык);
  if (имяПоНомеруВнешний) {
    const имя = чистоеИмя(имяПоНомеруВнешний(номер));
    if (имя) return имя;
  }
  return языки.текст('игрок', язык);
}

/** Номер места за столом (целое > 0) или 0, если его нет. */
function номерМеста(значениеМеста) {
  const число = Number(значениеМеста);
  return Number.isInteger(число) && число > 0 ? число : 0;
}

/** Текст письма для одного места; null — писать не о чем. */
function текстПисьма(данные, место, язык = 'ru') {
  const фраза = фразаИсхода(данные.игра, место.исход, язык);
  if (фраза === null) return null;
  const строки = [языки.текст(названиеИгры(данные.игра), язык) + ' — ' + фраза];

  const всеМеста = Array.isArray(данные.места) ? данные.места : [];
  const моёЧисло = Number(место.номер);
  const моёМесто = номерМеста(место.место);
  const местоНапарника = номерМеста(место.напарник);
  let напарник = null;
  const соперники = [];
  const виденные = new Set();
  for (const другой of всеМеста) {
    if (другой === место) continue;
    /* Тот же человек, севший за стол с двух устройств, себе не соперник. */
    if (!другой.этоБот && моёЧисло > 0 && Number(другой.номер) === моёЧисло) continue;
    if (местоНапарника && местоНапарника !== моёМесто && !напарник && номерМеста(другой.место) === местоНапарника) {
      напарник = другой;
      continue;
    }
    /* Один человек с двух устройств — один соперник, а не два. */
    const чужой = Number(другой.номер);
    if (!другой.этоБот && чужой > 0) {
      if (виденные.has(чужой)) continue;
      виденные.add(чужой);
    }
    соперники.push(имяМеста(другой, язык));
  }
  if (напарник) строки.push(языки.текст('Напарник', язык) + ': ' + имяМеста(напарник, язык));
  if (соперники.length) {
    const подпись = соперники.length === 1 ? 'Соперник' : (напарник ? 'Соперники' : 'За столом');
    строки.push(языки.текст(подпись, язык) + ': ' + списокИмён(соперники, язык));
  }
  if (место.исход !== 'внеСчёта') строки.push(строкаРейтинга(место.очков, язык));
  return строки.join('\n');
}

/** Значение зависимости: строка или функция, возвращающая строку. */
function значение(что) {
  try { return typeof что === 'function' ? что() : что; } catch (беда) { return ''; }
}

/** Кнопка «Играть ещё»: прямая (web_app) при адресе сайта, запасная
 *  (ссылка на бота с меткой игры) при имени бота, иначе кнопки нет. */
function кнопкаИграть(игра) {
  const строка = названия.словаИгры(игра);
  const адрес = String(значение(адресИгрыВнешний) || '').replace(/\/+$/, '');
  if (/^https:\/\//.test(адрес) && строка.страница) {
    return { text: 'Играть ещё', web_app: { url: адрес + '/' + encodeURI(строка.страница) } };
  }
  const бот = String(значение(имяБотаВнешний) || '').replace(/^@/, '');
  if (/^[A-Za-z0-9_]+$/.test(бот)) {
    const метка = названия.меткаИгры(игра);
    return { text: 'Играть ещё', url: 'https://t.me/' + бот + '?start=' + (метка ? 'invite_' + метка : 'invite') };
  }
  return null;
}

function кнопкиПисьма(игра, язык = 'ru') {
  const строка = [];
  const играть = кнопкаИграть(игра);
  if (играть) строка.push(играть);
  строка.push({ text: 'Не присылать итоги', callback_data: ОТКАЗ_ОТ_ИТОГОВ });
  return { inline_keyboard: [строка, [{ text: 'Позвать в другом чате', switch_inline_query: названиеИгры(игра) }]].map(ряд => ряд.map(кнопка => ({ ...кнопка, text: языки.текст(кнопка.text, язык) }))) };
}

/** Письмо целиком { текст, кнопки } или null. Экспортируется для проверок. */
function собратьПисьмо(данные, место) {
  const язык = языки.язык(языкПоНомеруВнешний?.(Number(место.номер)));
  const текст = текстПисьма(данные, место, язык);
  if (текст === null) return null;
  return { текст: текст, кнопки: кнопкиПисьма(данные.игра, язык) };
}

