/** Пишем ли этому месту: человек с номером; учтён рейтингом (есть
 *  очков) или партия «вне счёта»; бот и гость без номера — нет. */
function нужноПисать(место) {
  if (!место || место.этоБот) return false;
  const номер = Number(место.номер);
  if (!Number.isInteger(номер) || номер <= 0) return false;
  if (личины.этоЛичина(номер)) return false;   // у личины нет Telegram — писать некому
  if (место.исход === 'внеСчёта') return true;
  return Number.isFinite(Number(место.очков)) && место.очков !== null && место.очков !== undefined;
}

/** Есть ли за столом хоть кто-то, кроме одного человека: два места одного
 *  номера (один человек с двух устройств) — это «партия с самим собой», письма нет. */
function естьСоперник(места) {
  const разные = new Set();
  места.forEach(function (место, порядок) {
    if (!место) return;
    const номер = Number(место.номер);
    const человекСНомером = !место.этоБот && Number.isInteger(номер) && номер > 0;
    разные.add(человекСНомером ? 'н' + номер : 'м' + порядок);   // бот и гость без номера — каждый сам по себе
  });
  return разные.size >= 2;
}

function событие(данные) {
  if (!отправитьВнешний) return;             // не подключён — тихо ничего не делаем
  if (!данные || данные.что !== 'итог' || !Array.isArray(данные.места)) return;
  try {
    if (!естьСоперник(данные.места)) return;
    const письма = [];
    const собраны = new Set();               // номера, которым письмо уже собрано
    for (const место of данные.места) {
      /* Свой try на каждого: сбой на одном игроке (не прочли отказ,
         не собрали имя) лишает письма только его, а не весь стол. */
      try {
        if (!нужноПисать(место)) continue;
        const номер = Number(место.номер);
        if (собраны.has(номер)) continue;
        if (запрещено(номер)) continue;
        const собранное = собратьПисьмо(данные, место);
        if (!собранное) continue;
        собраны.add(номер);
        if (!местоВЧас(номер)) continue;
        письма.push({ номер: номер, текст: собранное.текст, кнопки: собранное.кнопки, повторялось: false });
      } catch (бедаИгрока) {
        /* этому игроку письма не будет, остальным — будут */
      }
    }
    if (письма.length) поставить(письма);
  } catch (беда) {
    /* сбой сборки писем партию ронять не должен */
  }
}

/** Забыть очередь и память пределов — только для проверок. */
function забытьВсё() {
  очередь = [];
  идётОтправка = false;
  итоговЧеловеку.clear();
}

