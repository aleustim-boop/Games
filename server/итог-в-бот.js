let отправитьВнешний = null;
let почемуНеЗватьВнешний = null;
let запретитьВнешний = null;
let имяПоНомеруВнешний = null;
let языкПоНомеруВнешний = null;
let адресИгрыВнешний = null;
let имяБотаВнешний = null;
let сейчасФункция = Date.now;
let отложитьФункция = настоящийТаймер;

/** Настоящий таймер, который не держит процесс живым (при остановке сервера). */
function настоящийТаймер(дело, мс) {
  const таймер = setTimeout(дело, мс);
  if (таймер && typeof таймер.unref === 'function') таймер.unref();
  return таймер;
}

/**
 * Подключить модуль к настоящему миру.
 *   отправить(тело)           — послать письмо; вернуть (или пообещать)
 *                                { ok, error_code, parameters } либо null.
 *   почемуНеЗвать(номер)       — '' | 'сам' | 'ботНеПишет'.
 *   запретить(номер, причина)  — запомнить отказ (при 403 — 'ботНеПишет').
 *   имяПоНомеру(номер)         — имя из подписи Telegram или ''.
 *   языкПоНомеру(номер)        — язык из проверенной подписи Telegram.
 *   адресИгры, имяБота         — строка или функция; для кнопки «Играть ещё».
 *   сейчас, отложить           — подменяемые часы для проверок.
 */
function подключить(зависимости) {
  зависимости = зависимости || {};
  отправитьВнешний = typeof зависимости.отправить === 'function' ? зависимости.отправить : null;
  почемуНеЗватьВнешний = typeof зависимости.почемуНеЗвать === 'function' ? зависимости.почемуНеЗвать : null;
  запретитьВнешний = typeof зависимости.запретить === 'function' ? зависимости.запретить : null;
  имяПоНомеруВнешний = typeof зависимости.имяПоНомеру === 'function' ? зависимости.имяПоНомеру : null;
  языкПоНомеруВнешний = typeof зависимости.языкПоНомеру === 'function' ? зависимости.языкПоНомеру : null;
  адресИгрыВнешний = зависимости.адресИгры || null;
  имяБотаВнешний = зависимости.имяБота || null;
  сейчасФункция = typeof зависимости.сейчас === 'function' ? зависимости.сейчас : Date.now;
  отложитьФункция = typeof зависимости.отложить === 'function' ? зависимости.отложить : настоящийТаймер;
}

/* ---------------------------------------------------------------------
   Очередь: одно письмо за раз, пауза между письмами.
   --------------------------------------------------------------------- */
let очередь = [];
let идётОтправка = false;
const итоговЧеловеку = new Map();      // номер → [времена постановки за последний час]

/** Запрещено ли писать этому номеру (отказ «сам» или 403 «ботНеПишет»). */
function запрещено(номер) {
  if (!почемуНеЗватьВнешний) return false;
  const причина = почемуНеЗватьВнешний(номер);
  return причина === 'сам' || причина === 'ботНеПишет';
}

/** Можно ли поставить ещё один итог этому человеку: не больше 30 в час. */
function местоВЧас(номер) {
  const сейчас = сейчасФункция();
  if (итоговЧеловеку.size > ПОТОЛОК_ПАМЯТИ_ЛЮДЕЙ) {
    for (const [чей, времена] of итоговЧеловеку) {
      const свежие = времена.filter(function (в) { return сейчас - в < ЧАС; });
      if (свежие.length) итоговЧеловеку.set(чей, свежие);
      else итоговЧеловеку.delete(чей);
    }
  }
  const свежие = (итоговЧеловеку.get(номер) || []).filter(function (в) { return сейчас - в < ЧАС; });
  if (свежие.length >= ИТОГОВ_В_ЧАС_ЧЕЛОВЕКУ) {
    итоговЧеловеку.set(номер, свежие);
    return false;
  }
  свежие.push(сейчас);
  итоговЧеловеку.set(номер, свежие);
  return true;
}

/** Взять из очереди следующее письмо; пусто — очередь спит. */
function следующее() {
  /* Зовётся из таймера: падение здесь уронило бы сервер, поэтому без
     пропусков и без исключений наружу. */
  try {
    while (очередь.length) {
      const письмо = очередь.shift();
      if (запрещено(письмо.номер)) continue;   // отказ мог прийти, пока письмо ждало
      идётОтправка = true;
      послать(письмо);
      return;
    }
  } catch (беда) {
    /* Не смогли решить, можно ли писать этому номеру, — это письмо
       пропускаем, остальные идут. Отметку «идёт отправка» поднимаем ДО
       таймера: иначе новое событие, пришедшее за время паузы, запустило
       бы второй поток писем без паузы (при первом запуске очереди
       отметка ещё снята). */
    if (очередь.length) {
      идётОтправка = true;
      try {
        отложитьФункция(следующее, ПАУЗА_МЕЖДУ_ПИСЬМАМИ);
        return;
      } catch (ещёБеда) {
        /* запланировать не вышло — снимаем отметку ниже, иначе очередь встала бы навсегда */
      }
    }
  }
  идётОтправка = false;
}

/** Разбор ответа Telegram. Тексты ошибок не читаем и не печатаем. */
function разобратьОтвет(письмо, итог) {
  const код = итог ? Number(итог.error_code) : 0;
  if (код === 403) {
    if (запретитьВнешний) запретитьВнешний(письмо.номер, 'ботНеПишет');
  } else if (код === 429 && !письмо.повторялось) {
    const сказано = Number(итог.parameters && итог.parameters.retry_after);
    const секунд = Math.min(ПОТОЛОК_ЖДАТЬ_ОТВЕТ, Number.isFinite(сказано) && сказано > 0 ? сказано : 1);
    письмо.повторялось = true;
    отложитьФункция(function () { послать(письмо); }, секунд * 1000);
    return;                                  // очередь ждёт этот повтор
  }
  отложитьФункция(следующее, ПАУЗА_МЕЖДУ_ПИСЬМАМИ);
}

function послать(письмо) {
  let обещание;
  try {
    обещание = Promise.resolve(отправитьВнешний({
      chat_id: письмо.номер,
      text: письмо.текст,
      reply_markup: письмо.кнопки
    }));
  } catch (беда) {
    обещание = Promise.resolve(null);
  }
  обещание.catch(function () { return null; }).then(function (итог) {
    try {
      разобратьОтвет(письмо, итог);
    } catch (беда) {
      /* Сбой разбора очередь не останавливает, но отметку «идёт отправка»
         не снимаем: следующее письмо уже запланировано, а снятая отметка
         дала бы второй поток писем без паузы. */
      try {
        отложитьФункция(следующее, ПАУЗА_МЕЖДУ_ПИСЬМАМИ);
      } catch (ещёБеда) {
        идётОтправка = false;                // запланировать не вышло — иначе очередь встала бы навсегда
      }
    }
  });
}

/** Поставить письма в очередь с потолком: лишнее старое выбрасываем. */
function поставить(письма) {
  for (const письмо of письма) очередь.push(письмо);
  if (очередь.length > ПОТОЛОК_ОЧЕРЕДИ) {
    const лишних = очередь.length - ПОТОЛОК_ОЧЕРЕДИ;
    очередь = очередь.slice(лишних);
    console.log('Итоги в бот: очередь полна, выброшено старых писем: ' + лишних);
  }
  if (!идётОтправка) следующее();
}

