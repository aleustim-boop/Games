const ПАУЗА_МЕЖДУ_ПИСЬМАМИ = 100;     // мс: не больше 10 писем в секунду
const ПОТОЛОК_ОЧЕРЕДИ = 500;          // писем в очереди; сверх — выбрасываем самые старые
const ПОТОЛОК_ЖДАТЬ_ОТВЕТ = 60;       // секунд: дольше retry_after не ждём
const ИТОГОВ_В_ЧАС_ЧЕЛОВЕКУ = 30;     // страховка от ботов-фермеров, живых не ограничивает
