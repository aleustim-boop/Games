'use strict';

/* =====================================================================
   ИТОГ В ЧАТ: когда партия за столом, открытым из группы, кончилась,
   бот пишет в эту группу одну строку с итогом — «Сыграли в шашки:
   Саша — победа, Петя — поражение.» — и кнопку «Реванш?».
   План: штаб/план-бот-группы.md, Э3.

   Тексты без рода и без склонения имён: пола Telegram не сообщает
   («Анна обыграл» — ошибка), а падеж ломается на иностранных и редких
   именах. Поэтому имя всегда в начальной форме, исход — словом рядом.

   Зачем. Группа видит, чем кончилась игра, и один нажатием садится
   за новый стол (кнопку ловит бот, callback_data «stol:<метка игры>»).

   Модуль ЧИСТЫЙ, как server/итог-в-бот.js: сети не открывает, файлов не
   трогает, про Telegram и ключ бота не знает. Всё внешнее — через
   подключить(). Пока отправить не задан, модуль выключен.
   Тексты ошибок Telegram не читаем и не печатаем: в них бывает адрес
   запроса, а в нём — ключ бота.

   Событие (его объявляет server/комнаты.js, этап Э4):
     { что: 'итог', чат, игра, места: [{ номер, этоБот, имя, исход, место, напарник }] }
     чат     — номер группы Telegram (целое < 0); нет или ≥ 0 — писать некуда;
     исход   — 'победа' | 'поражение' | 'ничья' | 'внеСчёта';
     напарник — номер МЕСТА напарника в игре парами или null;
     имя     — то, что человек набрал в игре: в текст НЕ идёт (подделка),
               имена берутся через имяПоНомеру из подписи Telegram.
   ===================================================================== */

const названия = require('./названия.js');

/* ---------------------------------------------------------------------
   Пределы.
   --------------------------------------------------------------------- */
const ПОРОГ_НА_ЧАТ = 3 * 60 * 1000;   // мс: не чаще одного итога в 3 минуты на чат (решение штаба)
const ПОТОЛОК_ЖДАТЬ_ОТВЕТ = 60;       // секунд: дольше retry_after не ждём
const ПОТОЛОК_ПАМЯТИ_ЧАТОВ = 5000;
const ИМЯ_В_ТЕКСТЕ = 32;

/* ---------------------------------------------------------------------
   Имена.
   --------------------------------------------------------------------- */

/** Имя без управляющих знаков и длинных хвостов (режем по знакам, не по кускам UTF-16). */
function чистоеИмя(имя) {
  return Array.from(String(имя || '').replace(/[\s\x00-\x1f]+/g, ' ').trim()).slice(0, ИМЯ_В_ТЕКСТЕ).join('');
}

/** «Лена», «Лена и Петя», «Лена, Петя и бот», «Лена, Петя и ещё 2». */
function списокИмён(имена) {
  if (имена.length <= 1) return имена.join('');
  if (имена.length === 2) return имена[0] + ' и ' + имена[1];
  if (имена.length === 3) return имена[0] + ', ' + имена[1] + ' и ' + имена[2];
  return имена[0] + ', ' + имена[1] + ' и ещё ' + (имена.length - 2);
}

/** Как назвать место: бот — «бот», человек с номером — имя из подписи
 *  Telegram, остальные (гость без Telegram) — «игрок». */
function имяМеста(место) {
  if (место.этоБот) return 'бот';
  const номер = Number(место.номер);
  if (Number.isInteger(номер) && номер > 0 && имяПоНомеруВнешний) {
    let имя = '';
    try { имя = чистоеИмя(имяПоНомеруВнешний(номер)); } catch (беда) { имя = ''; }
    if (имя) return имя;
  }
  return 'игрок';
}

/** Люди за столом без повторов: один человек с двух устройств — один, бот и
 *  гость без номера — каждый сам по себе. */
function местаБезПовторов(места) {
  const виденные = new Set();
  const итог = [];
  for (const место of места) {
    if (!место || typeof место !== 'object') continue;
    const номер = Number(место.номер);
    if (!место.этоБот && Number.isInteger(номер) && номер > 0) {
      if (виденные.has(номер)) continue;
      виденные.add(номер);
    }
    итог.push(место);
  }
  return итог;
}

/* ---------------------------------------------------------------------
   Тексты.
   --------------------------------------------------------------------- */

function имена(места) { return места.map(имяМеста); }

/** Текст итога; null — писать не о чем (исход незнаком). */
function текстИтога(данные, места) {
  const игра = данные.игра;
  const слова = названия.словаИгры(игра);
  const вИгру = слова.вИгру;
  const победили = места.filter(function (м) { return м.исход === 'победа'; });
  const проиграли = места.filter(function (м) { return м.исход === 'поражение'; });
  const всеИнеСчёта = места.length > 0 && места.every(function (м) { return м.исход === 'внеСчёта'; });
  const всеНичья = места.length > 0 && места.every(function (м) { return м.исход === 'ничья'; });

  if (всеИнеСчёта) {
    return списокИмён(имена(места)) + ' закончили по согласию партию ' + вИгру + '.';
  }
  if (всеНичья) {
    return списокИмён(имена(места)) + ' сыграли вничью ' + вИгру + '.';
  }

  /* Дурак: кто остался в дураках и кто вышел (сбросил карты). */
  if (игра === 'дурак') {
    if (!проиграли.length) return null;
    const начало = 'В дураках: ' + имена(проиграли).join(', ') + '.';
    const вышли = имена(места.filter(function (м) { return м.исход !== 'поражение'; }));
    return вышли.length ? начало + ' Вышли: ' + вышли.join(', ') + '.' : начало;
  }

  if (!победили.length) return null;

  /* Парами: победители с напарником против проигравших. */
  const играютПарами = места.some(function (м) { return Number(м.напарник) > 0; });
  if (играютПарами && победили.length >= 2 && проиграли.length >= 1) {
    return 'Сыграли ' + вИгру + ': ' + списокИмён(имена(победили)) + ' — победа, ' +
      списокИмён(имена(проиграли)) + ' — поражение.';
  }

  if (места.length === 2 && победили.length === 1 && проиграли.length === 1) {
    return 'Сыграли ' + вИгру + ': ' + имяМеста(победили[0]) + ' — победа, ' + имяМеста(проиграли[0]) + ' — поражение.';
  }

  const остальные = места.filter(function (м) { return м.исход !== 'победа'; });
  const голова = 'Победа: ' + имена(победили).join(', ') + '.';
  return остальные.length ? голова + ' За столом: ' + имена(остальные).join(', ') + '.' : голова;
}

/** Кнопка «Реванш?»: метка игры нужна боту, чтобы открыть новый стол; нет метки — нет кнопки. */
function кнопкиИтога(игра) {
  const метка = названия.меткаИгры(игра);
  if (!метка) return undefined;
  return { inline_keyboard: [[{ text: 'Реванш?', callback_data: 'stol:' + метка }]] };
}

/** Сообщение целиком { текст, кнопки } или null. Экспортируется для проверок. */
function собратьСообщение(данные) {
  const места = местаБезПовторов(Array.isArray(данные.места) ? данные.места : []);
  const текст = текстИтога(данные, места);
  if (текст === null) return null;
  return { текст: текст, кнопки: кнопкиИтога(данные.игра) };
}

/* ---------------------------------------------------------------------
   Зависимости.
   --------------------------------------------------------------------- */
let отправитьВнешний = null;
let имяПоНомеруВнешний = null;
let сейчасФункция = Date.now;
let отложитьФункция = настоящийТаймер;

/** Настоящий таймер, который не держит процесс живым при остановке сервера. */
function настоящийТаймер(дело, мс) {
  const таймер = setTimeout(дело, мс);
  if (таймер && typeof таймер.unref === 'function') таймер.unref();
  return таймер;
}

/**
 * Подключить модуль к настоящему миру.
 *   отправить(тело)    — послать сообщение { chat_id, text, reply_markup };
 *                         вернуть (или пообещать) { ok, error_code, description, parameters } либо null.
 *   имяПоНомеру(номер) — first_name из подписи Telegram или ''.
 *   сейчас, отложить   — подменяемые часы для проверок.
 */
function подключить(зависимости) {
  зависимости = зависимости || {};
  отправитьВнешний = typeof зависимости.отправить === 'function' ? зависимости.отправить : null;
  имяПоНомеруВнешний = typeof зависимости.имяПоНомеру === 'function' ? зависимости.имяПоНомеру : null;
  сейчасФункция = typeof зависимости.сейчас === 'function' ? зависимости.сейчас : Date.now;
  отложитьФункция = typeof зависимости.отложить === 'function' ? зависимости.отложить : настоящийТаймер;
}

/* ---------------------------------------------------------------------
   Память: забытые чаты, переезды групп, время последнего итога.
   --------------------------------------------------------------------- */
const забытыеЧаты = new Set();         // куда писать нельзя (бота выгнали, чата нет)
const новыйНомерЧата = new Map();      // старый номер → номер после переезда в супергруппу
const последнийИтог = new Map();       // чат → время последнего итога

function подрезать(карта) {
  if (карта.size <= ПОТОЛОК_ПАМЯТИ_ЧАТОВ) return;
  const лишних = карта.size - ПОТОЛОК_ПАМЯТИ_ЧАТОВ;
  let убрано = 0;
  for (const ключ of карта.keys()) {
    if (убрано++ >= лишних) break;
    карта.delete(ключ);
  }
}

/** Не рано ли снова писать в этот чат; можно — сразу отмечает время. */
function местоПоПорогу(чат) {
  const сейчас = сейчасФункция();
  const было = последнийИтог.get(чат);
  if (было !== undefined && сейчас - было < ПОРОГ_НА_ЧАТ) return false;
  последнийИтог.set(чат, сейчас);
  if (последнийИтог.size > ПОТОЛОК_ПАМЯТИ_ЧАТОВ) {
    for (const [ключ, время] of последнийИтог) {
      if (сейчас - время >= ПОРОГ_НА_ЧАТ) последнийИтог.delete(ключ);
    }
    подрезать(последнийИтог);
  }
  return true;
}

/* ---------------------------------------------------------------------
   Отправка и разбор ответа.
   --------------------------------------------------------------------- */

/** Чат, в который писать нельзя: 403 (бота выгнали или заблокировали) или «chat not found». */
function чатНедоступен(итог) {
  const код = Number(итог.error_code);
  if (код === 403) return true;
  return /chat not found/i.test(String(итог.description || ''));
}

function разобратьОтвет(сообщение, итог) {
  if (!итог || итог.ok) return;
  if (чатНедоступен(итог)) {
    забытыеЧаты.add(сообщение.чат);
    подрезать(забытыеЧаты);
    return;
  }
  const код = Number(итог.error_code);
  if (код === 429 && !сообщение.повторял429) {
    const сказано = Number(итог.parameters && итог.parameters.retry_after);
    const секунд = Math.min(ПОТОЛОК_ЖДАТЬ_ОТВЕТ, Number.isFinite(сказано) && сказано > 0 ? сказано : 1);
    сообщение.повторял429 = true;
    отложитьФункция(function () { послать(сообщение); }, секунд * 1000);
    return;
  }
  const новый = Number(итог.parameters && итог.parameters.migrate_to_chat_id);
  if (Number.isInteger(новый) && новый < 0 && !сообщение.повторялПереезд) {
    /* Группа стала супергруппой: старый номер больше не годится.
       Запоминаем новый, чтобы следующие итоги шли сразу туда. */
    новыйНомерЧата.set(сообщение.чат, новый);
    подрезать(новыйНомерЧата);
    сообщение.повторялПереезд = true;
    сообщение.чат = новый;
    последнийИтог.set(новый, сейчасФункция());
    послать(сообщение);
  }
}

function послать(сообщение) {
  if (забытыеЧаты.has(сообщение.чат)) return;   // за время ожидания чат могли забыть
  let обещание;
  try {
    const тело = { chat_id: сообщение.чат, text: сообщение.текст };
    if (сообщение.кнопки) тело.reply_markup = сообщение.кнопки;
    обещание = Promise.resolve(отправитьВнешний(тело));
  } catch (беда) {
    return;                                      // отправка упала сразу — повторять нечем
  }
  обещание.catch(function () { return null; }).then(function (итог) {
    try { разобратьОтвет(сообщение, итог); } catch (беда) { /* сбой разбора партию не роняет */ }
  });
}

/* ---------------------------------------------------------------------
   Вход.
   --------------------------------------------------------------------- */

/** Считаются живые люди: не боты; один человек с двух устройств — один. */
function людей(места) {
  return местаБезПовторов(места).filter(function (м) { return !м.этоБот; }).length;
}

function событие(данные) {
  if (!отправитьВнешний) return;                 // не подключён — тихо ничего не делаем
  if (!данные || данные.что !== 'итог' || !Array.isArray(данные.места)) return;
  try {
    let чат = Number(данные.чат);
    if (нетГруппы(данные.чат, чат)) return;
    if (новыйНомерЧата.has(чат)) чат = новыйНомерЧата.get(чат);
    if (забытыеЧаты.has(чат)) return;
    if (людей(данные.места) < 2) return;
    const собранное = собратьСообщение(данные);
    if (!собранное) return;
    if (!местоПоПорогу(чат)) return;             // порог проверяем последним: он отмечает время
    послать({ чат: чат, текст: собранное.текст, кнопки: собранное.кнопки, повторял429: false, повторялПереезд: false });
  } catch (беда) {
    /* сбой сборки итога партию ронять не должен */
  }
}

/** Нет чата или чат не группа: номера групп Telegram — целые отрицательные. */
function нетГруппы(сырое, число) {
  return сырое === null || сырое === undefined || сырое === '' || !Number.isInteger(число) || число >= 0;
}

/** Забыть всё — только для проверок. */
function забытьВсё() {
  забытыеЧаты.clear();
  новыйНомерЧата.clear();
  последнийИтог.clear();
}

module.exports = {
  подключить: подключить,
  событие: событие,
  собратьСообщение: собратьСообщение,
  ПОРОГ_НА_ЧАТ: ПОРОГ_НА_ЧАТ,
  забытьВсё: забытьВсё
};
