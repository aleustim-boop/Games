'use strict';

/* =====================================================================
   ВОЗВРАТ УШЕДШИХ: письма «давно не заходили» через 3 и через 14 дней.
   План: штаб/план-возврат-ушедших.md, этап Э2.

   Модуль сети не открывает и таймеров не заводит, как server/турнир-письма.js.
   Он отвечает на вопрос «каким людям пора письмо прямо сейчас» и отдаёт
   список; отправку (по одному, с разбором 403/429) делает сервер.
   Сам пишет только маленький файл памяти возврат-ушедших.json.

   Письмо: { номер, текст, кнопки, вид }
     номер — число, Telegram-номер получателя;
     текст — готовая строка по-русски;
     кнопки — { inline_keyboard } одной строкой: «Играть» (web_app на https-адрес,
              иначе ссылка на бота, иначе её нет) и «Не присылать»
              (callback_data = ОТКАЗ_ОТ_ВОЗВРАТА);
     вид   — '3дня' | '14дней'.

   Правила:
   - тишина = сейчас − последнийРаз; от 3 до 10 дней — письмо «3 дня»,
     от 10 до 14 — ничего (ждём 14), от 14 до 28 — «14 дней»; дольше 28 не пишем;
   - за одну тишину каждое письмо уходит не больше одного раза; человеку
     с тишиной 20 дней и пустой памятью — одно письмо «14 дней», не два;
   - вернулся (последнийРаз стал новее отметки тишинаС) — отметки письмо3/письмо14
     сбрасываются, а время последнего письма (последнееПисьмо) остаётся:
     после любого письма меньше 7 дней — никаких писем;
   - файл памяти был испорчен: в новом файле стоит флаг послеПорчи, и на первом
     проходе модуль только ПРОСТАВЛЯЕТ отметки «письмо уже было» (3–14 дней →
     письмо3, 14–28 → письмо14) без отправки. Запись с испорченным тишинаС —
     то же самое, но для этого одного человека;
   - шлём только с 12:00 до 19:00 по Москве; за проход — не больше 20 писем,
     у кого тишина длиннее — раньше;
   - отметки ложатся на диск ДО выдачи писем; не легли — отметки снимаем,
     писем нет (потерять лучше, чем отправить дважды);
   - файл памяти не читается с диска — писем нет весь день; не разбирается —
     файл уходит в «.битый», дальше см. послеПорчи.

   Москва = UTC+3 без перехода на летнее время. Считаем от UTC САМИ, только
   методы getUTC*: боевая машина живёт по UTC, машина штаба по +02:00,
   getHours() дал бы разные окна.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const гдеДанные = require('./папка-данных.js');

/* ---------------------------------------------------------------------
   Пределы
   --------------------------------------------------------------------- */
const ЧАС = 60 * 60 * 1000;
const СУТКИ = 24 * ЧАС;
const ПОРОГ_ПЕРВОГО_ПИСЬМА = 3 * СУТКИ;
const ПОТОЛОК_ПЕРВОГО_ПИСЬМА = 10 * СУТКИ;   // «3 дня» только до 10 дней тишины; дальше ждём 14
const ПОРОГ_ВТОРОГО_ПИСЬМА = 14 * СУТКИ;
const ПАУЗА_МЕЖДУ_ПИСЬМАМИ = 7 * СУТКИ;      // после любого письма неделю не пишем
const ДАЛЬШЕ_НЕ_ПИШЕМ = 28 * СУТКИ;
const ХРАНИТЬ_ЗАПИСЬ = 35 * СУТКИ;
const СДВИГ_МОСКВЫ = 3 * ЧАС;
const ОКНО_С_ЧАСА = 12;     // включительно, по Москве
const ОКНО_ДО_ЧАСА = 19;    // не включая: последний проход начинается до 19:00
const ПИСЕМ_ЗА_ПРОХОД = 20;

/* Слово кнопки отказа. Бот (bot/бот.js) знает то же слово: разойдутся — кнопка умрёт молча. */
const ОТКАЗ_ОТ_ВОЗВРАТА = 'не-возврат';

/* ---------------------------------------------------------------------
   Подключение
   --------------------------------------------------------------------- */
let последниеЗаходы = null;
let почемуНеПисать = null;
let этоЛичина = function () { return false; };
let турнирДня = null;
let адресИгры = null;
let имяБота = null;
let сейчасФункция = Date.now;
let папкаДанных = null;
let память = null;

/**
 * Подключить источники.
 *   последниеЗаходы — (сейчасМс) → [{ номер, последнийРаз }];
 *   почемуНеПисать  — (номер) → '' | причина; пусто = можно (все отказы учитывает она сама);
 *   этоЛичина       — (номер) → true для личины;
 *   турнирДня       — (сейчасМс) → { игра, состояние } для строки про турнир;
 *   адресИгры       — строка или функция: адрес сайта https://…;
 *   имяБота         — строка или функция: имя бота для запасной кнопки-ссылки;
 *   сейчас          — часы в мс;
 *   папка           — своя папка для файла памяти (проверкам).
 */
function подключить(зависимости) {
  зависимости = зависимости || {};
  последниеЗаходы = typeof зависимости.последниеЗаходы === 'function' ? зависимости.последниеЗаходы : null;
  почемуНеПисать = typeof зависимости.почемуНеПисать === 'function' ? зависимости.почемуНеПисать : null;
  этоЛичина = typeof зависимости.этоЛичина === 'function' ? зависимости.этоЛичина : function () { return false; };
  турнирДня = typeof зависимости.турнирДня === 'function' ? зависимости.турнирДня : null;
  адресИгры = зависимости.адресИгры || null;
  имяБота = зависимости.имяБота || null;
  сейчасФункция = typeof зависимости.сейчас === 'function' ? зависимости.сейчас : Date.now;
  папкаДанных = typeof зависимости.папка === 'string' && зависимости.папка ? зависимости.папка : null;
  память = null;   // папка могла смениться — читаем заново
}

function времяСейчас(сейчасМс) {
  return Number.isFinite(сейчасМс) ? сейчасМс : сейчасФункция();
}

function значение(что) {
  try { return typeof что === 'function' ? что() : что; } catch (беда) { return ''; }
}

/* ---------------------------------------------------------------------
   Время по Москве (только getUTC*)
   --------------------------------------------------------------------- */
function москваСдвинутая(мс) {
  return new Date(мс + СДВИГ_МОСКВЫ);
}

function часПоМоскве(мс) {
  return москваСдвинутая(мс).getUTCHours();
}

/** Ид дня по Москве ГГГГ-ММ-ДД: к нему привязана «сломанность» памяти. */
function идДняПоМоскве(мс) {
  const д = москваСдвинутая(мс);
  return д.getUTCFullYear() + '-' + String(д.getUTCMonth() + 1).padStart(2, '0') + '-' + String(д.getUTCDate()).padStart(2, '0');
}

function вОкнеОтправки(мс) {
  const час = часПоМоскве(мс);
  return час >= ОКНО_С_ЧАСА && час < ОКНО_ДО_ЧАСА;
}

/* ---------------------------------------------------------------------
   Память: { люди: { "<номер>": { тишинаС, письмо3, письмо14, последнееПисьмо } },
             послеПорчи: true|false, сломанаВ (только в оперативной памяти) }
   письмо3/письмо14 — время письма за текущую тишину (сбрасываются при заходе);
   последнееПисьмо — время любого письма, заход его не стирает.
   --------------------------------------------------------------------- */
function папкаПамяти() {
  return папкаДанных || гдеДанные.папка();
}

function файлПамяти() {
  return path.join(папкаПамяти(), 'возврат-ушедших.json');
}

function прочитатьПамять(идДня) {
  const результат = { люди: {}, сломанаВ: '', послеПорчи: false };
  let текст;
  try {
    текст = fs.readFileSync(файлПамяти(), 'utf8');
  } catch (беда) {
    if (беда && беда.code === 'ENOENT') {
      /* Файла нет, но рядом лежит «битый»: порча была, новый файл не лёг — письма снова не шлём. */
      if (fs.existsSync(файлПамяти() + '.битый')) результат.послеПорчи = true;
      return результат;
    }
    console.error('Возврат ушедших: файл памяти не читается, в этот день писем нет.');
    результат.сломанаВ = идДня;
    return результат;
  }
  try {
    const разобрано = JSON.parse(текст);
    if (!разобрано || typeof разобрано.люди !== 'object' || !разобрано.люди || Array.isArray(разобрано.люди)) throw new Error('форма');
    for (const ключ of Object.keys(разобрано.люди)) {
      const з = разобрано.люди[ключ];
      const число = function (в) { return Number.isFinite(в) ? в : 0; };
      const запись = {
        тишинаС: 0,
        письмо3: число(з && з.письмо3),
        письмо14: число(з && з.письмо14),
        последнееПисьмо: 0
      };
      /* Старый формат без последнееПисьмо: берём позднейшую из двух отметок. */
      запись.последнееПисьмо = Number.isFinite(з && з.последнееПисьмо) ? з.последнееПисьмо : Math.max(запись.письмо3, запись.письмо14);
      /* Любое из полей отметок, если оно есть, обязано быть конечным числом ≥ 0. */
      const поляЦелы = з && ['тишинаС', 'письмо3', 'письмо14', 'последнееПисьмо'].every(function (имя) {
        return з[имя] === undefined && имя !== 'тишинаС' || (Number.isFinite(з[имя]) && з[имя] >= 0);
      });
      if (поляЦелы && з.непонятно !== true) запись.тишинаС = з.тишинаС;
      else запись.непонятно = true;   // испорчено поле: считаем «письма уже были», отметки проставим без отправки
      результат.люди[ключ] = запись;
    }
    результат.послеПорчи = разобрано.послеПорчи === true;
  } catch (беда) {
    console.error('Возврат ушедших: файл памяти испорчен, первый проход только проставит отметки.');
    try { fs.renameSync(файлПамяти(), файлПамяти() + '.битый'); } catch (ещёБеда) { /* останется на месте */ }
    результат.люди = {};
    результат.послеПорчи = true;
    результат.записатьСразу = true;   // флаг должен лечь в новый файл, пока не пришла рассылка
  }
  return результат;
}

/** Память на этот день или null, если она не читается (писать нельзя). */
function памятьДня(идДня) {
  if (!память || (память.сломанаВ && память.сломанаВ !== идДня)) {
    память = прочитатьПамять(идДня);
    if (память.записатьСразу) {
      delete память.записатьСразу;
      сохранитьПамять();   // не легло — флаг живёт в оперативной памяти, писем всё равно нет
    }
  }
  return память.сломанаВ === идДня ? null : память;
}

/** Записать через временный файл. true — файл лёг на диск. */
function сохранитьПамять() {
  try {
    fs.mkdirSync(папкаПамяти(), { recursive: true });
    const временный = файлПамяти() + '.пишем';
    fs.writeFileSync(временный, JSON.stringify({ люди: память.люди, послеПорчи: память.послеПорчи === true }), 'utf8');
    fs.renameSync(временный, файлПамяти());
    return true;
  } catch (беда) {
    console.error('Возврат ушедших: память не записалась на диск; писем нет, попробуем в следующий проход.');
    return false;
  }
}

/** Выбросить записи старше ХРАНИТЬ_ЗАПИСЬ; вернёт, что выброшено (чтобы вернуть при сбое диска). */
function убратьСтарые(мс) {
  const выброшено = {};
  for (const ключ of Object.keys(память.люди)) {
    if (мс - память.люди[ключ].тишинаС > ХРАНИТЬ_ЗАПИСЬ) {
      выброшено[ключ] = память.люди[ключ];
      delete память.люди[ключ];
    }
  }
  return выброшено;
}

