function названиеТурнира(игра) {
  return игра === 'дурак' ? 'турнир по дураку' : 'турнир';
}

/** Турнир сегодня и ещё не начался (запись до 20:00 МСК) — иначе null. */
function турнирСегодня(мс) {
  if (!турнирДня) return null;
  try {
    const т = турнирДня(мс);
    /* Без времени начала строки про турнир не будет: время берём только из источника. */
    return т && т.состояние === 'запись' && Number.isFinite(т.началоМс) ? т : null;
  } catch (беда) {
    return null;
  }
}

/** Время начала по Москве, ЧЧ:ММ (только getUTC*). */
function времяНачала(началоМс) {
  const д = москваСдвинутая(началоМс);
  return String(д.getUTCHours()).padStart(2, '0') + ':' + String(д.getUTCMinutes()).padStart(2, '0');
}

function текстПисьма(вид, турнир) {
  if (вид === '3дня') {
    const строки = ['Давно не виделись! Дурак, шашки, нарды и другие игры ждут вас.'];
    if (турнир) строки.push('Сегодня в ' + времяНачала(турнир.началоМс) + ' по Москве — ' + названиеТурнира(турнир.игра) + ', можно записаться прямо в игре.');
    else строки.push('Загляните — соперник найдётся за минуту.');
    return строки.join('\n');
  }
  const строки = ['Две недели без партии — пора вернуться! Новые соперники уже за столами.'];
  if (турнир) строки.push('Сегодня в ' + времяНачала(турнир.началоМс) + ' по Москве — ' + названиеТурнира(турнир.игра) + '.');
  строки.push('Это последнее напоминание: больше напоминать не будем, пока вы снова не зайдёте.');
  return строки.join('\n');
}

/** Кнопки: «Играть» (web_app → ссылка на бота → нет) и «Не присылать». */
function кнопкиПисьма(вДеньТурнира) {
  const адрес = String(значение(адресИгры) || '').replace(/\/+$/, '');
  const бот = String(значение(имяБота) || '').replace(/^@/, '').trim();
  const ряд = [];
  if (/^https:\/\//.test(адрес)) {
    const хвост = вДеньТурнира ? 'index.html#' + encodeURIComponent('турнир') : 'index.html';
    ряд.push({ text: 'Играть', web_app: { url: адрес + '/' + хвост } });
  } else if (бот) {
    ряд.push({ text: 'Играть', url: 'https://t.me/' + бот + '?start=invite' });
  }
  ряд.push({ text: 'Не присылать', callback_data: ОТКАЗ_ОТ_ВОЗВРАТА });
  return { inline_keyboard: [ряд] };
}

/* ---------------------------------------------------------------------
   Выбор письма и проход
   --------------------------------------------------------------------- */

/** Нет ли отказа. Сбой источника отказов — не пишем (лучше промолчать). */
function можноПисать(номер) {
  try {
    if (этоЛичина(номер)) return false;
    if (!почемуНеПисать) return true;
    return !почемуНеПисать(номер);
  } catch (беда) {
    return false;
  }
}

/** Какое письмо нужно при такой тишине и таких отметках: '3дня' | '14дней' | ''. */
function какоеПисьмо(тишина, запись, мс) {
  if (тишина < ПОРОГ_ПЕРВОГО_ПИСЬМА || тишина > ДАЛЬШЕ_НЕ_ПИШЕМ) return '';
  if (мс - запись.последнееПисьмо < ПАУЗА_МЕЖДУ_ПИСЬМАМИ) return '';   // письмо было меньше недели назад
  if (тишина >= ПОРОГ_ВТОРОГО_ПИСЬМА) return запись.письмо14 ? '' : '14дней';
  if (тишина >= ПОТОЛОК_ПЕРВОГО_ПИСЬМА) return '';   // 10–14 дней: ждём «14 дней»
  return запись.письмо3 ? '' : '3дня';
}

/** Запись человека для этой тишины: новая, если заходил после прошлой отметки.
 *  Время последнего письма при возвращении сохраняется. */
function записьДляТишины(номерКлюч, последнийРаз) {
  const есть = память.люди[номерКлюч];
  if (есть && есть.тишинаС >= последнийРаз) return есть;
  return { тишинаС: последнийРаз, письмо3: 0, письмо14: 0, последнееПисьмо: есть ? есть.последнееПисьмо : 0 };
}

/** Отметка «письмо уже было» без отправки (после порчи памяти). */
function отметкаБезПисьма(номерКлюч, последнийРаз, мс) {
  const есть = память.люди[номерКлюч];
  const тишина = мс - последнийРаз;
  const запись = { тишинаС: последнийРаз, письмо3: 0, письмо14: 0, последнееПисьмо: есть ? есть.последнееПисьмо : 0 };
  if (тишина >= ПОРОГ_ПЕРВОГО_ПИСЬМА && тишина < ПОРОГ_ВТОРОГО_ПИСЬМА) запись.письмо3 = мс;
  else if (тишина >= ПОРОГ_ВТОРОГО_ПИСЬМА && тишина <= ДАЛЬШЕ_НЕ_ПИШЕМ) запись.письмо14 = мс;
  if (запись.письмо3 || запись.письмо14) запись.последнееПисьмо = мс;
  return запись;
}

/** Свернуть список заходов по номеру: одному номеру — одна запись с самым поздним заходом. */
function свернутьЗаходы(список) {
  const поНомеру = new Map();
  for (const заход of список || []) {
    const номер = Number(заход && заход.номер);
    const последнийРаз = Number(заход && заход.последнийРаз);
    if (!Number.isInteger(номер) || номер <= 0 || !Number.isFinite(последнийРаз)) continue;
    if (!поНомеру.has(номер) || поНомеру.get(номер) < последнийРаз) поНомеру.set(номер, последнийРаз);
  }
  return поНомеру;
}

function собрать(мс) {
  if (!вОкнеОтправки(мс)) return [];
  if (!последниеЗаходы) return [];
  const идДня = идДняПоМоскве(мс);
  if (!памятьДня(идДня)) return [];

  const заходы = свернутьЗаходы(последниеЗаходы(мс));
  const былоЛюдей = Object.assign({}, память.люди);
  const былоПослеПорчи = память.послеПорчи;
  const послеПорчи = память.послеПорчи === true;
  let проставлено = false;

  const нужные = [];
  for (const [номер, последнийРаз] of заходы) {
    const ключ = String(номер);
    const есть = память.люди[ключ];
    /* После порчи (всей памяти или этой записи) письма не шлём: проставляем «уже было». */
    if (послеПорчи || (есть && есть.непонятно)) {
      const тишина = мс - последнийРаз;
      if (послеПорчи || есть || (тишина >= ПОРОГ_ПЕРВОГО_ПИСЬМА && тишина <= ДАЛЬШЕ_НЕ_ПИШЕМ)) {
        const отметка = отметкаБезПисьма(ключ, последнийРаз, мс);
        /* После порчи пауза в 7 дней отсчитывается от этого прохода для всех заходивших. */
        if (послеПорчи) отметка.последнееПисьмо = мс;
        память.люди[ключ] = отметка;
        проставлено = true;
      }
      continue;
    }
    const запись = записьДляТишины(ключ, последнийРаз);
    const тишина = мс - последнийРаз;
    const вид = какоеПисьмо(тишина, запись, мс);
    if (!вид) continue;
    if (!можноПисать(номер)) continue;
    нужные.push({ номер: номер, вид: вид, тишина: тишина, запись: запись });
  }
  if (послеПорчи) {
    /* Первый проход после порчи — только отметки. Пустой список заходов флаг не снимает:
       возможно, посещения ещё не загрузились. */
    if (!заходы.size) return [];
    память.послеПорчи = false;
    проставлено = true;
  }

  /* Кто молчит дольше — раньше; остальные дождутся следующего прохода. */
  нужные.sort(function (а, б) { return б.тишина - а.тишина; });
  const выбранные = послеПорчи ? [] : нужные.slice(0, ПИСЕМ_ЗА_ПРОХОД);
  if (!выбранные.length && !проставлено) return [];

  /* Отметки ставим до выдачи; прежнее помним, чтобы снять при сбое диска. */
  убратьСтарые(мс);
  for (const п of выбранные) {
    const новая = Object.assign({}, п.запись);
    if (п.вид === '3дня') новая.письмо3 = мс;
    else новая.письмо14 = мс;
    новая.последнееПисьмо = мс;
    память.люди[String(п.номер)] = новая;
  }
  if (!сохранитьПамять()) {
    память.люди = былоЛюдей;
    память.послеПорчи = былоПослеПорчи;
    return [];
  }

  const турнир = турнирСегодня(мс);
  return выбранные.map(function (п) {
    return { номер: п.номер, текст: текстПисьма(п.вид, турнир), кнопки: кнопкиПисьма(!!турнир), вид: п.вид };
  });
}

/**
 * Письма на момент сейчасМс. Пусто вне окна 12:00–19:00 МСК и при любом сбое.
 * Не больше 20 писем за проход, отметки уже стоят на диске.
 */
function письмаНаСейчас(сейчасМс) {
  try {
    return собрать(времяСейчас(сейчасМс));
  } catch (беда) {
    console.error('Возврат ушедших: сбой при сборке писем, писем нет.');
    return [];
  }
}

