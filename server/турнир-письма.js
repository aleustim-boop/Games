'use strict';

/* =====================================================================
   ПИСЬМА ТУРНИРА: напоминание за 10 минут и итог после турнира.
   План: штаб/план-турниры.md, этап Э9.

   Модуль сети не открывает и таймеров не заводит, как server/итог-в-бот.js.
   Он отвечает на вопрос «какие письма пора отправить прямо сейчас» и
   отдаёт их списком; отправку и таймер подключает провод в server/сервер.js.
   Единственное, что он пишет сам, — маленький файл памяти «кому уже
   отправлено». Любой сбой внутри — пустой список, наружу ничего не бросаем.

   Письмо: { номер, текст, кнопки, вид }
     номер — Telegram-номер получателя (только для отправки, в текст не идёт);
     текст — готовая строка по-русски;
     кнопки — { inline_keyboard } с кнопкой web_app на index.html#турнир
              или null (адреса https нет — письмо без кнопки);
     вид   — 'напоминание' | 'итог' | 'не-состоялся' (для журнала).

   Как провод шлёт (разослатьПоОдному(письма, отправить, отложить)):
     отправить(письмо) шлёт ОДНО письмо в Telegram телом
       { chat_id: письмо.номер, text: письмо.текст, reply_markup: письмо.кнопки }
       (reply_markup не ставить, если кнопки null) и возвращает ответ
       Telegram { ok, error_code, parameters } — прямо или обещанием; null
       при сбое сети. Тексты ошибок модуль не читает и не печатает.
     отложить(дело, мс) — таймер (setTimeout, лучше с unref).
     Разбор ответа, как у итог-в-бот.js: 403 — запретить(номер, 'ботНеПишет')
     (человек заблокировал бота); 429 — одна повторная попытка через
     parameters.retry_after секунд (не больше минуты). Перед КАЖДЫМ письмом
     отказ спрашивается заново: отказался во время рассылки — письма нет.

   Правила:
   - напоминание — только записавшимся на сегодня, окно: последние
     10 минут до начала (19:50–20:00 МСК); одно в день на человека;
   - итог — один раз за день, когда турнир окончен (после доигрыша,
     20:40 МСК): тем, кто сыграл хоть партию или записался ДО начала
     (по записанМс из турниры.участники — раньше начала турнира);
     тем, кто просто зашёл посмотреть в ходе турнира, итога нет.
     Состоялся — место, очки, победитель; нет — «не набралось соперников»;
   - личины писем не получают; отказ 'сам' и 'ботНеПишет' — письма нет;
   - запись в турнир — согласие ровно на одно напоминание и один итог.

   Память лежит в файле рядом с остальными данными (через временный файл,
   как server/турниры.js): после перезапуска сервера второго письма нет.
   Файл есть, но не читается — в этот день писем не шлём (потерять лучше,
   чем отправить дважды). Файл не записался — сообщение в console.error
   (без текста ошибки), письма идут, память живёт до перезапуска.

   Время и источники (турниры, отказ, адрес сайта) подключаются через
   подключить({...}): проверка подставляет свои.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const гдеДанные = require('./папка-данных.js');
const личины = require('./личины.js');
const турнирыНастоящие = require('./турниры.js');

/* ---------------------------------------------------------------------
   Пределы
   --------------------------------------------------------------------- */
const МИНУТА = 60 * 1000;
const ЗА_СКОЛЬКО_НАПОМИНАТЬ = 10 * МИНУТА;   // 19:50 при начале в 20:00
const ПАУЗА_МЕЖДУ_ПИСЬМАМИ = 100;            // мс: не больше 10 писем в секунду
const ПОТОЛОК_ЖДАТЬ_ОТВЕТ = 60;              // секунд: дольше retry_after не ждём
const ХРАНИТЬ_ДНЕЙ = 14;                      // записей «отправлено» держим не дольше
const ИМЯ_В_ПИСЬМЕ = 32;

/* ---------------------------------------------------------------------
   Подключение
   --------------------------------------------------------------------- */
let турниры = турнирыНастоящие;
let почемуНеЗвать = null;
let запретитьВнешний = null;
let этоЛичина = личины.этоЛичина;
let адресИгры = null;
let сейчасФункция = Date.now;
let папкаДанных = null;
let память = null;

/**
 * Подключить источники.
 *   турниры       — как server/турниры.js (турнирДня, участники, таблица, итогДня, местоИгрока);
 *   почемуНеЗвать — (номер) → '' | 'сам' | 'ботНеПишет'; не задан — пишем всем;
 *   запретить     — (номер, причина): запомнить отказ (при 403 — 'ботНеПишет');
 *   этоЛичина     — (номер) → true для личины;
 *   адресИгры     — строка или функция: адрес сайта https://… для кнопки;
 *   сейчас        — часы в мс;
 *   папка         — своя папка для файла памяти (проверкам).
 */
function подключить(зависимости) {
  зависимости = зависимости || {};
  турниры = зависимости.турниры || турнирыНастоящие;
  почемуНеЗвать = typeof зависимости.почемуНеЗвать === 'function' ? зависимости.почемуНеЗвать : null;
  запретитьВнешний = typeof зависимости.запретить === 'function' ? зависимости.запретить : null;
  этоЛичина = typeof зависимости.этоЛичина === 'function' ? зависимости.этоЛичина : личины.этоЛичина;
  адресИгры = зависимости.адресИгры || null;
  сейчасФункция = typeof зависимости.сейчас === 'function' ? зависимости.сейчас : Date.now;
  папкаДанных = typeof зависимости.папка === 'string' && зависимости.папка ? зависимости.папка : null;
  память = null;   // папка могла смениться — читаем заново
}

function времяСейчас(сейчасМс) {
  return Number.isFinite(сейчасМс) ? сейчасМс : сейчасФункция();
}

/* ---------------------------------------------------------------------
   Память «уже отправлено»:
   { дни: { <ид турнира>: { напомнено: [номера], итог: true|false } }, сломанаВ: <ид дня> | '' }
   --------------------------------------------------------------------- */
function файлПамяти() {
  return папкаДанных ? path.join(папкаДанных, 'турнир-письма.json') : гдеДанные.файл('турнир-письма.json');
}

function папкаПамяти() {
  return папкаДанных || гдеДанные.папка();
}

/** Прочитать файл. Нет файла — чистый лист. Есть, но не читается или
 *  не разбирается — день помечаем сломанным (писем не будет). Тексты ошибок не печатаем. */
function прочитатьПамять(идДня) {
  const результат = { дни: {}, сломанаВ: '' };
  let текст;
  try {
    текст = fs.readFileSync(файлПамяти(), 'utf8');
  } catch (беда) {
    if (беда && беда.code === 'ENOENT') return результат;
    console.error('Письма турнира: файл памяти не читается, в этот день писем не шлём.');
    результат.сломанаВ = идДня;
    return результат;
  }
  try {
    const разобрано = JSON.parse(текст);
    if (!разобрано || typeof разобрано.дни !== 'object' || !разобрано.дни) throw new Error('форма');
    for (const ид of Object.keys(разобрано.дни)) {
      const д = разобрано.дни[ид] || {};
      результат.дни[ид] = {
        напомнено: Array.isArray(д.напомнено) ? д.напомнено.filter(Number.isInteger) : [],
        итог: д.итог === true
      };
    }
  } catch (беда) {
    console.error('Письма турнира: файл памяти испорчен, в этот день писем не шлём.');
    /* Откладываем испорченный файл в сторону: завтра начнём с чистого листа. */
    try { fs.renameSync(файлПамяти(), файлПамяти() + '.битый'); } catch (ещёБеда) { /* останется на месте */ }
    результат.дни = {};
    результат.сломанаВ = идДня;
  }
  return результат;
}

/** Запись дня или null, если память в этот день сломана (писать нельзя). */
function записьДня(ид) {
  if (!память || (память.сломанаВ && память.сломанаВ !== ид)) память = прочитатьПамять(ид);
  if (память.сломанаВ === ид) return null;
  if (!память.дни[ид]) память.дни[ид] = { напомнено: [], итог: false };
  return память.дни[ид];
}

/** Записать на диск через временный файл; старые дни выбрасываем. */
function сохранитьПамять() {
  const идыПоПорядку = Object.keys(память.дни).sort();   // в ид есть дата ГГГГ-ММ-ДД: по порядку = по времени
  while (идыПоПорядку.length > ХРАНИТЬ_ДНЕЙ) delete память.дни[идыПоПорядку.shift()];
  try {
    fs.mkdirSync(папкаПамяти(), { recursive: true });
    const временный = файлПамяти() + '.пишем';
    fs.writeFileSync(временный, JSON.stringify({ дни: память.дни }), 'utf8');
    fs.renameSync(временный, файлПамяти());
  } catch (беда) {
    console.error('Письма турнира: память не записалась на диск; письма идут, повтор после перезапуска возможен.');
  }
}

/* ---------------------------------------------------------------------
   Тексты и кнопка
   --------------------------------------------------------------------- */

/** Имя для письма: без управляющих знаков и длинных хвостов (эмодзи не режем пополам). */
function чистоеИмя(имя) {
  const строка = Array.from(String(имя || '').replace(/[\s\x00-\x1f]+/g, ' ').trim()).slice(0, ИМЯ_В_ПИСЬМЕ).join('');
  return строка || 'Игрок';
}

function значение(что) {
  try { return typeof что === 'function' ? что() : что; } catch (беда) { return ''; }
}

/** «очко» / «очка» / «очков» под число. */
function словоОчко(число) {
  const о10 = число % 10;
  const о100 = число % 100;
  if (о10 === 1 && о100 !== 11) return 'очко';
  if (о10 >= 2 && о10 <= 4 && (о100 < 12 || о100 > 14)) return 'очка';
  return 'очков';
}

function очки(число) {
  return число + ' ' + словоОчко(число);
}

/** «Турнир по дураку»: у игры без склонения — просто «Турнир». */
function названиеТурнира(игра) {
  return игра === 'дурак' ? 'Турнир по дураку' : 'Турнир';
}

/** Кнопка входа в турнир: web_app на index.html#турнир; нет https-адреса — кнопки нет. */
function кнопки(текстКнопки) {
  const адрес = String(значение(адресИгры) || '').replace(/\/+$/, '');
  if (!/^https:\/\//.test(адрес)) return null;
  return { inline_keyboard: [[{ text: текстКнопки, web_app: { url: адрес + '/index.html#' + encodeURIComponent('турнир') } }]] };
}

/** Минуты до начала считаем от настоящего времени: письмо могло уйти не ровно в 19:50. */
function текстНапоминания(игра, доНачалаМс) {
  const минут = Math.ceil(доНачалаМс / МИНУТА);
  const начало = минут <= 1 ? ' вот-вот начнётся.' : ' начнётся через ' + минут + ' мин.';
  return названиеТурнира(игра) + начало + '\nНажмите кнопку, чтобы зайти и сыграть.';
}

function текстНеСостоялся(игра) {
  return названиеТурнира(игра) + ' закончился. В этот раз не набралось соперников.\nЗавтра будет новый турнир.';
}

function текстНеИграл(игра) {
  return названиеТурнира(игра) + ' закончился. Вы не сыграли ни одной партии.\nЗавтра будет новый турнир.';
}

function текстМеста(игра, строка, победитель, участников) {
  const строки = [названиеТурнира(игра) + ' закончился.'];
  строки.push('Ваше место: ' + строка.место + ' из ' + участников + '. Набрано: ' + очки(строка.очки) + '.');
  if (строка.место === 1) строки.push('Вы победили!');
  else if (победитель) строки.push('Победитель: ' + чистоеИмя(победитель.имя) + ', ' + очки(победитель.очки) + '.');
  return строки.join('\n');
}

/* ---------------------------------------------------------------------
   Кому можно писать
   --------------------------------------------------------------------- */

/** Нет ли отказа. Сбой чтения отказа — не пишем (лучше промолчать). */
function можноПисать(номер) {
  if (этоЛичина(номер)) return false;
  if (!почемуНеЗвать) return true;
  try {
    const причина = почемуНеЗвать(номер);
    return причина !== 'сам' && причина !== 'ботНеПишет';
  } catch (беда) {
    return false;
  }
}

function этоНомерЧеловека(номер) {
  return Number.isInteger(номер) && номер > 0;
}

/* ---------------------------------------------------------------------
   Напоминание
   --------------------------------------------------------------------- */

function собратьНапоминания(мс) {
  const турнир = турниры.турнирДня(мс);
  if (!турнир || турнир.состояние !== 'запись') return [];
  const доНачала = турнир.началоМс - мс;
  if (!(доНачала > 0 && доНачала <= ЗА_СКОЛЬКО_НАПОМИНАТЬ)) return [];

  const день = записьДня(турнир.ид);
  if (!день) return [];
  const письма = [];
  for (const человек of турниры.участники(турнир.ид)) {
    if (!этоНомерЧеловека(человек.номер)) continue;
    if (день.напомнено.indexOf(человек.номер) !== -1) continue;
    if (!можноПисать(человек.номер)) continue;
    письма.push({
      номер: человек.номер,
      текст: текстНапоминания(турнир.игра, доНачала),
      кнопки: кнопки('Открыть турнир'),
      вид: 'напоминание'
    });
  }
  /* Отметки ставим только когда письма собраны целиком: сбой посередине ничего не помечает. */
  if (письма.length) {
    for (const письмо of письма) день.напомнено.push(письмо.номер);
    сохранитьПамять();
  }
  return письма;
}

/**
 * Письма-напоминания на момент сейчасМс. Пусто вне окна 19:50–20:00 МСК,
 * в день без турнира и при любом сбое. Каждому записавшемуся — одно за день.
 */
function письмаНапоминания(сейчасМс) {
  try {
    return собратьНапоминания(времяСейчас(сейчасМс));
  } catch (беда) {
    console.error('Письма турнира: сбой при сборке напоминаний, писем нет.');
    return [];
  }
}

/* ---------------------------------------------------------------------
   Итог
   --------------------------------------------------------------------- */

/** Записался ли человек до начала турнира (по записанМс из турниры.участники). */
function записанДоНачала(человек, началоМс) {
  return Number.isFinite(человек.записанМс) && человек.записанМс < началоМс;
}

function собратьИтог(мс) {
  const турнир = турниры.турнирДня(мс);
  if (!турнир || турнир.состояние !== 'окончен') return [];
  const день = записьДня(турнир.ид);
  if (!день || день.итог) return [];

  const итог = турниры.итогДня(турнир.ид);
  const всегоВТаблице = итог.состоялся ? турниры.таблица(турнир.ид).length : 0;
  const победитель = итог.состоялся && итог.тройка.length ? итог.тройка[0] : null;

  const письма = [];
  for (const человек of турниры.участники(турнир.ид)) {
    if (!этоНомерЧеловека(человек.номер)) continue;
    const место = турниры.местоИгрока(турнир.ид, человек.номер);
    /* Просто зашедшим посмотреть итога нет: нужна игра или запись до начала. */
    const своя = место || записанДоНачала(человек, турнир.началоМс);
    if (!своя) continue;
    if (!можноПисать(человек.номер)) continue;
    let текст;
    let вид = 'итог';
    if (!итог.состоялся) {
      текст = текстНеСостоялся(турнир.игра);
      вид = 'не-состоялся';
    } else if (место) {
      текст = текстМеста(турнир.игра, место, победитель, всегоВТаблице);
    } else {
      текст = текстНеИграл(турнир.игра);
    }
    письма.push({ номер: человек.номер, текст: текст, кнопки: кнопки('Открыть турнир'), вид: вид });
  }
  день.итог = true;
  сохранитьПамять();
  return письма;
}

/**
 * Письма итога на момент сейчасМс. Пусто, пока турнир не окончен (до
 * 20:40 МСК), в день без турнира и при любом сбое; один раз за день.
 */
function письмаИтога(сейчасМс) {
  try {
    return собратьИтог(времяСейчас(сейчасМс));
  } catch (беда) {
    console.error('Письма турнира: сбой при сборке итога, писем нет.');
    return [];
  }
}

/* ---------------------------------------------------------------------
   Рассылка для провода: письма по одному, не чаще 10 в секунду
   --------------------------------------------------------------------- */

/** Можно ли слать это письмо: оно целое и отказа нет (спрашиваем заново). */
function годноКОтправке(письмо) {
  try {
    return !!письмо && typeof письмо === 'object' && можноПисать(письмо.номер);
  } catch (беда) {
    return false;
  }
}

/**
 * Разослать письма по одному с паузой ПАУЗА_МЕЖДУ_ПИСЬМАМИ. Формы
 * отправить и отложить — в шапке модуля. Наружу ничего не бросает:
 * не смогли запланировать следующее письмо — рассылка обрывается.
 */
function разослатьПоОдному(письма, отправить, отложить) {
  if (!Array.isArray(письма) || typeof отправить !== 'function' || typeof отложить !== 'function') return;
  const список = письма.filter(function (п) { return п && typeof п === 'object'; }).map(function (п) { return Object.assign({}, п); });

  function запланировать(дело, мс) {
    try {
      отложить(дело, мс);
    } catch (беда) {
      console.error('Письма турнира: не вышло запланировать следующее письмо, рассылка оборвана.');
    }
  }

  function дальше() {
    if (список.length) запланировать(следующее, ПАУЗА_МЕЖДУ_ПИСЬМАМИ);
  }

  function следующее() {
    try {
      while (список.length) {
        const письмо = список.shift();
        if (!годноКОтправке(письмо)) continue;
        послать(письмо);
        return;
      }
    } catch (беда) {
      дальше();
    }
  }

  function разобратьОтвет(письмо, итог) {
    const код = итог ? Number(итог.error_code) : 0;
    if (код === 403) {
      if (запретитьВнешний) {
        try { запретитьВнешний(письмо.номер, 'ботНеПишет'); } catch (беда) { /* не запомнили — не страшно */ }
      }
    } else if (код === 429 && !письмо.повторялось) {
      const сказано = Number(итог.parameters && итог.parameters.retry_after);
      const секунд = Math.min(ПОТОЛОК_ЖДАТЬ_ОТВЕТ, Number.isFinite(сказано) && сказано > 0 ? сказано : 1);
      письмо.повторялось = true;
      запланировать(function () {
        if (годноКОтправке(письмо)) послать(письмо);
        else дальше();
      }, секунд * 1000);
      return;   // очередь ждёт этот повтор
    }
    дальше();
  }

  function послать(письмо) {
    let ожидание;
    try {
      ожидание = Promise.resolve(отправить(письмо));
    } catch (беда) {
      ожидание = Promise.resolve(null);
    }
    ожидание.catch(function () { return null; }).then(function (итог) {
      try {
        разобратьОтвет(письмо, итог);
      } catch (беда) {
        дальше();
      }
    });
  }

  следующее();
}

