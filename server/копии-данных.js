'use strict';

/* =====================================================================
   ЕЖЕДНЕВНЫЕ КОПИИ ДАННЫХ.

   Зачем. В server/данные лежат настоящие имена и номера живых людей:
   знакомства, статистика, раздача дня, рейтинг. Однажды эти файлы уже
   стёрли — проверки писали прямо в боевую папку, — и восстановить их
   было неоткуда: копий не было, а в git такие файлы не едут и не должны.
   Дыру с проверками закрыли (см. server/папка-данных.js), но она была
   не единственным способом потерять данные: остаются испорченная запись,
   ошибка в новом коде и обычное «случайно удалил не то».

   КОГДА СНИМАЕТСЯ КОПИЯ — при запуске сервера и ДО того, как он начнёт
   писать. Не по расписанию посреди работы, и это решение, а не мелочь:
   файл, скопированный в середине записи, выглядит целым, а внутри у него
   обрывок. Такая копия хуже отсутствующей — на неё надеются.

   СКОЛЬКО ХРАНИМ — семь последних дней, а не одну копию. Испорченная
   копия, затёршая единственную хорошую, — это ровно та же беда, от
   которой мы защищаемся.

   ГДЕ ЛЕЖАТ — внутри самой папки данных, в «копии». Там их закрывает
   тот же .gitignore, что и сами данные: чужие имена и номера не должны
   уехать в git ни в каком виде, в том числе копией.

   ЧТО ДЕЛАТЬ, ЕСЛИ ДАННЫЕ ВСЁ-ТАКИ ПРОПАЛИ. Копии — обычные файлы,
   их видно глазами: server/данные/копии/2026-09-08/знакомые.json.
   Вернуть можно руками, а можно этим файлом:

       node -e "require('./server/копии-данных.js').восстановить()"

   — он возьмёт самую свежую копию и положит файлы на место, а прежние
   отодвинет с пометкой «.до-восстановления», чтобы и их можно было
   посмотреть. Сервер при этом должен быть остановлен.
   ===================================================================== */

const fs = require('fs');
const path = require('path');

const гдеДанные = require('./папка-данных.js');

/* Сколько дней держим копии. Неделя — достаточный запас, чтобы заметить
   пропажу: за это время владелец успевает открыть игру хотя бы раз. */
const КОПИЙ_ХРАНИМ = 7;

/** Папка с копиями внутри папки данных. */
function папкаКопий() {
  return path.join(гдеДанные.папка(), 'копии');
}

/** «2026-09-08» — имя копии за сегодня. */
function ключДня(время) {
  const дата = new Date(время === undefined ? Date.now() : время);
  const месяц = String(дата.getMonth() + 1).padStart(2, '0');
  const число = String(дата.getDate()).padStart(2, '0');
  return дата.getFullYear() + '-' + месяц + '-' + число;
}

/** Копируем только сами данные: json без временных «.пишем». */
function этоФайлДанных(имя) {
  return имя.endsWith('.json') && !имя.endsWith('.пишем');
}

/** Какие копии уже лежат — по порядку, свежая последняя. */
function копии() {
  let имена = [];
  try {
    имена = fs.readdirSync(папкаКопий());
  } catch (сбой) {
    return [];                 // папки нет — копий тоже нет, это не беда
  }
  return имена.filter(function (имя) {
    return /^\d{4}-\d{2}-\d{2}$/.test(имя);
  }).sort();
}

/**
 * Снять копию за сегодня, если её ещё нет.
 *
 * Одна копия в сутки нарочно: сервер за день перезапускают много раз,
 * и снимай мы копию на каждый запуск, за сутки набралось бы полсотни
 * одинаковых, а семидневный запас превратился бы в двухчасовой.
 *
 * Возвращает сводку — её сервер говорит вслух при запуске.
 */
function снятьКопию() {
  const сегодня = ключДня();
  const куда = path.join(папкаКопий(), сегодня);
  let скопировано = 0;

  try {
    const файлы = fs.readdirSync(гдеДанные.папка()).filter(этоФайлДанных);
    if (файлы.length === 0) return сводка();       // копировать нечего

    if (!fs.existsSync(куда)) {
      fs.mkdirSync(куда, { recursive: true });
      for (const имя of файлы) {
        fs.copyFileSync(path.join(гдеДанные.папка(), имя), path.join(куда, имя));
        скопировано++;
      }
    }
    прибратьСтарые();
  } catch (сбой) {
    /* Не вышло — не повод не запускать игру. Сводка ниже честно покажет,
       что свежей копии нет, и это будет видно в записи при запуске. */
  }

  const итог = сводка();
  итог.скопировано = скопировано;
  return итог;
}

/** Выбросить копии старше семи последних. */
function прибратьСтарые() {
  const все = копии();
  const лишние = все.slice(0, Math.max(0, все.length - КОПИЙ_ХРАНИМ));
  for (const день of лишние) {
    try {
      fs.rmSync(path.join(папкаКопий(), день), { recursive: true, force: true });
    } catch (сбой) {
      /* Не удалилось — не беда: лишняя копия никому не мешает. */
    }
  }
}

/** Сколько копий лежит и от какого числа самая свежая. */
function сводка() {
  const все = копии();
  return {
    копий: все.length,
    свежая: все.length ? все[все.length - 1] : '',
    папка: папкаКопий()
  };
}

/** Одной строкой для записи при запуске — её читает человек. */
function словами() {
  const итог = сводка();
  if (!итог.копий) return 'Копий данных пока нет — первая появится при следующем запуске.';
  return 'Копий данных: ' + итог.копий + ', самая свежая от ' + итог.свежая + '.';
}

/**
 * Вернуть данные из копии. По умолчанию — из самой свежей.
 * Прежние файлы не стираем, а отодвигаем с пометкой: вдруг спасать
 * надо было как раз их.
 *
 * Сервер при восстановлении должен быть остановлен: иначе он допишет
 * своё поверх возвращённого и всё повторится.
 */
function восстановить(день) {
  const все = копии();
  const какая = день || (все.length ? все[все.length - 1] : '');
  if (!какая || все.indexOf(какая) === -1) {
    return { ок: false, причина: 'Такой копии нет. Есть: ' + (все.join(', ') || 'ни одной') };
  }

  const откуда = path.join(папкаКопий(), какая);
  const куда = гдеДанные.папка();
  const вернули = [];
  try {
    for (const имя of fs.readdirSync(откуда).filter(этоФайлДанных)) {
      const рабочий = path.join(куда, имя);
      if (fs.existsSync(рабочий)) {
        fs.renameSync(рабочий, рабочий + '.до-восстановления');
      }
      fs.copyFileSync(path.join(откуда, имя), рабочий);
      вернули.push(имя);
    }
  } catch (сбой) {
    return { ок: false, причина: 'Не вышло вернуть: ' + сбой.message, вернули: вернули };
  }
  return { ок: true, копия: какая, вернули: вернули };
}

module.exports = {
  КОПИЙ_ХРАНИМ: КОПИЙ_ХРАНИМ,
  папкаКопий: папкаКопий,
  копии: копии,
  снятьКопию: снятьКопию,
  сводка: сводка,
  словами: словами,
  восстановить: восстановить
};
