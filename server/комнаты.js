/**
 * Запомнить, что случилось: место, название и имя того, с кем это случилось.
 *
 * «Кто» здесь — тот, с кем событие произошло, а не обязательно тот, кто
 * нажал кнопку. По этому месту потом подставляется имя в рассказе, и если
 * назвать здесь автора хода, игрок прочитает про себя чужое действие.
 *
 * Зачем хранить ещё и имя. Рассказ собирается позже — в ту минуту, когда
 * игрок спросит новости, — и раньше имя искали по живому списку сидящих.
 * Для вышедшего из прихожей искать его негде: он из комнаты уже вычеркнут,
 * и остальные читали «Игрок 2 вышел из комнаты» вместо «Боря». Поэтому имя
 * запоминаем в тот же миг, когда случилось событие. Четвёртый довод нужен
 * ровно для этого случая: место уже освободилось, имя приходится назвать
 * заранее. Во всех остальных случаях имя берётся из комнаты само.
 */
/* ---------------------------------------------------------------------
   Пересадка: хозяин меняет двоих за столом местами

   Зачем это нужно. В игре парами напарник определяется МЕСТОМ — через
   одного, — и до сих пор человек не мог выбрать, с кем играет: кто раньше
   вошёл, тот и напарник. Пересадка отдаёт этот выбор хозяину стола.

   Почему именно обмен двоих, а не «перетащить на свободное место».
   Обмен — это перестановка содержимого двух ячеек, и у неё есть свойство,
   которое дороже удобства: число занятых мест при ней не меняется никогда.
   Значит ни задвоить игрока, ни потерять его нельзя даже теоретически —
   ни при каком стечении обстоятельств, ни при чьём-то входе в ту же секунду.
   --------------------------------------------------------------------- */

/** Ключ места по его номеру (1..мест) или null, если такого места нет. */
function местоПоНомеру(комната, номер) {
  if (typeof номер !== 'number' || !Number.isInteger(номер)) return null;
  if (номер < 1 || номер > комната.мест) return null;
  return партии.МЕСТА[номер - 1] || null;
}

/**
 * Поправить служебное имя после переезда. Имена «Игрок 2» и «Бот 3»
 * построены из номера места, и на новом месте они врут.
 *
 * Переименовываем ТОЛЬКО того, чьё имя и правда служебное — то есть в
 * точности такое, каким его дал бы сервер на прежнем месте. Всё остальное
 * — имя человека, и трогать его нельзя ни в коем случае.
 *
 * Почему проверка именно такая, а не «бот — значит переименовать». Игрок,
 * вышедший посреди партии, помечается ботом, но имя ему нарочно оставляют
 * своё: за столом должно быть видно, что это место Петра, за которого
 * теперь доигрывают. Переименуй мы его при пересадке — Пётр превратился бы
 * в «Бот 4», и человек пропал бы у всех с экрана. Ровно эту беду когда-то
 * уже чинили в «выйти», и заводить её заново нельзя.
 */
function поправитьИмяПоМесту(комната, место, староеМесто) {
  const игрок = комната.игроки[место];
  if (!игрок) return;
  if (игрок.имя === партии.имяБота(староеМесто)) {
    игрок.имя = партии.имяБота(место);
  } else if (игрок.имя === партии.имяПоУмолчанию(староеМесто)) {
    игрок.имя = партии.имяПоУмолчанию(место);
  }
  // Во всех прочих случаях имя человеческое — оставляем как есть.
}

/**
 * Поменять местами двоих за столом. Распоряжается только хозяин и только
 * до раздачи карт — это проверяет сервер, а не игра: страница может
 * показывать что угодно, но право на пересадку живёт здесь.
 */
function пересадить(комната, ктоЯ, намерение) {
  /* Право спрашиваем у общей проверки — той же, что у «начать», «настроек»
     и кнопок с ботами. Своей копии правила здесь нет нарочно: копия сперва
     расходится в словах (после партии человек читал бы «карты уже розданы»,
     хотя они давно сыграны), а потом отстаёт и по сути — добавят условие
     в общую проверку, а пересадка его не получит. В этом проекте так уже
     расходились несколько раз. */
  const нельзя = можноРаспоряжаться(комната, ктоЯ);
  if (нельзя) return нельзя;

  const откуда = местоПоНомеру(комната, намерение ? намерение.откуда : null);
  const куда = местоПоНомеру(комната, намерение ? намерение.куда : null);
  if (!откуда || !куда) {
    return { принято: false, причина: 'За этим столом такого места нет' };
  }
  if (откуда === куда) {
    return { принято: false, причина: 'Это одно и то же место' };
  }

  const пусто = !комната.игроки[откуда] && !комната.игроки[куда];
  if (пусто) {
    return { принято: false, причина: 'Оба места пустые — менять нечего' };
  }

  поменятьМестами(комната, откуда, куда);
  записатьСобытие(комната, комната.хозяин, 'пересадил');
  разбудить(комната);
  return { принято: true, событие: 'пересадил' };
}

/**
 * Сам обмен двух мест. Вынесен отдельно, потому что дверей к нему две:
 * «поменять местами двоих» (это распоряжение хозяина) и «сделать
 * напарником» (это просьба игрока про себя). Правила у дверей разные,
 * а перестановка обязана быть одна: разойдись эти два куска хоть в
 * мелочи — и одна из дорог однажды забыла бы переставить, скажем,
 * висящие опросы, а поймать такое почти нечем.
 */
function поменятьМестами(комната, откуда, куда) {
  const первый = комната.игроки[откуда] || null;
  const второй = комната.игроки[куда] || null;

  /* Сам обмен. Делается одним куском, без ожиданий внутри: «половины
     пересадки» существовать не может. */
  if (второй) комната.игроки[откуда] = второй;
  else delete комната.игроки[откуда];
  if (первый) комната.игроки[куда] = первый;
  else delete комната.игроки[куда];

  // Хозяин — это МЕСТО, и вместе с человеком переезжает и оно.
  if (комната.хозяин === откуда) комната.хозяин = куда;
  else if (комната.хозяин === куда) комната.хозяин = откуда;

  // Служебное имя считаем от того места, откуда игрок приехал.
  поправитьИмяПоМесту(комната, откуда, куда);
  поправитьИмяПоМесту(комната, куда, откуда);

  /* Знак внимания тоже помнит место. Смайлик виден восемь секунд, и если
     пересадить в эти секунды, признак «это я сам» достался бы новому
     жильцу места. Путаница косметическая, но чинится одной строкой. */
  const знак = комната.знакВнимания;
  if (знак) {
    if (знак.кто === откуда) знак.кто = куда;
    else if (знак.кто === куда) знак.кто = откуда;
  }

  /* Те, кто держит длинный опрос, помнят себя по МЕСТУ. Не переставь мы
     их вместе с игроками — человек получил бы вид чужого места: увидел бы
     себя под чужим именем, а если переехал хозяин, то и чужие кнопки
     хозяина. Ошибка тихая, поэтому чиним её здесь же, а не «потом». */
  for (const ждущий of комната.ждущие) {
    if (ждущий.ктоЯ === откуда) ждущий.ктоЯ = куда;
    else if (ждущий.ктоЯ === куда) ждущий.ктоЯ = откуда;
  }

  комната.трогали = Date.now();
}

/* ---------------------------------------------------------------------
   «Сделать напарником» — то же самое одним касанием

   Зачем отдельная дверь, если обмен местами уже есть. Человек за парным
   столом думает не «поменяйте местами второго и четвёртого», а «хочу вот
   этого себе в напарники». Прежняя пересадка отвечала на первый вопрос:
   два касания и умственная работа — сообразить, кого с кем менять. Эта
   дверь отвечает на второй: одно касание, а кого с кем переставить,
   считает сервер.

   Кто может. Любой игрок за столом — но только ПРО СЕБЯ: меняются
   местами выбранный и нынешний напарник просящего, а сам он не двигается.
   Хозяину при этом остаётся и прежняя пересадка — ею он рассаживает
   чужих людей, а не себя.

   Почему не только хозяин. Владелец сказал про это от первого лица —
   «хочу поменять СВОЕГО напарника». Оставь мы право одному хозяину,
   трое из четверых по-прежнему не могут ничего и должны просить голосом.
   Опасности в этом нет: обмен не меняет числа занятых мест (потерять
   или задвоить игрока невозможно), а до раздачи карт положение за столом
   ни на что, кроме пар, не влияет.
   --------------------------------------------------------------------- */

/**
 * Кто сейчас напарник этого места. Считаем ТЕМ ЖЕ правилом, что и вид
 * для игрока (правила.партнёр), а не «через одного» своими руками:
 * вторая копия правила рассадки однажды разойдётся с первой, и стол
 * начнёт врать про пары молча.
 */
function нынешнийНапарник(комната, место) {
  return играКомнаты(комната).напарник(занятыеМеста(комната), место);
}

/**
 * Сделать выбранного игрока своим напарником.
 *
 * Право проверяет сервер, а не страница: страница может показывать что
 * угодно, но переставить людей за столом можно только отсюда.
 */
function сделатьНапарником(комната, ктоЯ, намерение) {
  if (комната.этап === 'игра') {
    return { принято: false, причина: 'Карты уже розданы — стол теперь не поменять' };
  }
  if (комната.этап === 'конец') {
    return {
      принято: false,
      причина: 'Эта партия закончена. Нажмите «Сыграть ещё» — стол останется прежним'
    };
  }
  if (!комната.парами) {
    return { принято: false, причина: 'Напарники бывают только в игре парами, 2 на 2' };
  }

  const кого = местоПоНомеру(комната, намерение ? намерение.кого : null);
  if (!кого) {
    return { принято: false, причина: 'За этим столом такого места нет' };
  }
  if (кого === ктоЯ) {
    return { принято: false, причина: 'Это вы сами' };
  }
  /* Пустое место напарником не сделаешь. Обмен с пустым сам по себе законен
     (так освобождают место рядом), но это уже не «хочу вот его в напарники»,
     а другое желание — и просить его надо другой кнопкой, иначе человек
     нечаянно отправит своего напарника на пустое место. */
  if (!комната.игроки[кого]) {
    return { принято: false, причина: 'Здесь пока никто не сидит' };
  }

  const мойНапарник = нынешнийНапарник(комната, ктоЯ);
  if (!мойНапарник) {
    /* Такое бывает, пока за стол сели не все четверо: кто с кем в паре,
       ещё не решено, и переставлять нечего. */
    return {
      принято: false,
      причина: 'Пары ещё не сложились: подождите, пока за стол сядут все четверо'
    };
  }
  if (кого === мойНапарник) {
    return { принято: false, причина: 'Этот игрок уже ваш напарник' };
  }

  поменятьМестами(комната, кого, мойНапарник);
  /* Событие пишем от имени просившего: это его выбор, а не распоряжение
     хозяина, и в ленте новостей у остальных должно стоять его имя. */
  записатьСобытие(комната, ктоЯ, 'пересадил');
  разбудить(комната);
  return { принято: true, событие: 'пересадил' };
}

/* ---------------------------------------------------------------------
   Знаки внимания: смайлики и готовые фразы

   Свободного текста в этой переписке нет вовсе — по сети едет только
   номер из списка, который живёт в правилах (js/game.js). Поэтому
   проверять нечего, кроме самого номера: ни разметки, ни длины,
   ни грубых слов тут появиться не может.
   --------------------------------------------------------------------- */

/* Сколько знак виден за столом. Дольше держать нельзя: смайлик — это
   отклик на то, что происходит прямо сейчас, а не запись в тетради. */
const ЗНАК_ЖИВЁТ = 8 * 1000;

/* Защита от частых нажатий. Она нужна ровно из-за одной фразы — «Ходи!»:
   ею одной можно испортить человеку всю партию, если жать без остановки.
   Два правила сразу: короткая пауза после каждого знака и потолок на
   полтора десятка секунд — иначе пять быстрых нажатий подряд проходили бы
   каждые две секунды и стол всё равно засыпало бы. */
const ПАУЗА_МЕЖДУ_ЗНАКАМИ = 2 * 1000;
const ЗНАКОВ_ЗА_ОКНО = 5;
const ОКНО_ЗНАКОВ = 15 * 1000;

/* Броски — знаки с адресатом («кинуть в соперника») — жёстче: у них есть
   в кого попасть, и частый бросок в одного человека — уже не шутка.
   Не чаще одного в три секунды и не больше трёх за то же окно. */
const ПАУЗА_МЕЖДУ_БРОСКАМИ = 3 * 1000;
const БРОСКОВ_ЗА_ОКНО = 3;

/** Знак, который ещё виден. Протухший не показываем и наружу не отдаём. */
function свежийЗнак(комната) {
  const знак = комната.знакВнимания;
  if (!знак) return null;
  return (Date.now() - знак.когда <= ЗНАК_ЖИВЁТ) ? знак : null;
}

/**
 * Записать знак и разбудить стол. Здесь нет ни одной проверки нарочно:
 * этой же дорогой ходят боты, а их проверять не от кого — номер им даёт
 * не сеть, а сами правила. Всё, что приходит от живого игрока, проверяется
 * выше, в послатьЗнакВнимания.
 */
function записатьЗнакВнимания(комната, ктоЯ, номер, цель) {
  const игрок = комната.игроки[ктоЯ];
  const адресат = цель ? комната.игроки[цель] : null;
  комната.номерЗнака++;
  комната.знакВнимания = {
    кто: ктоЯ,
    номер: номер,
    имя: игрок ? игрок.имя : null,
    /* В кого кинули: внутреннее имя места и имя человека. Наружу уйдёт
       только имя и признак «в меня» — место выбросит видДляИгрока. */
    цель: адресат ? цель : null,
    имяЦели: адресат ? адресат.имя : null,
    когда: Date.now(),
    порядковый: комната.номерЗнака
  };
  комната.трогали = Date.now();
}

/**
 * В кого кинули — по кресту или по имени. Кресло надёжнее (имена за столом
 * могут совпадать), но игра называет людей именами — принимаем оба.
 * Только те, кто сидит за столом и не ушёл; бот — тоже мишень.
 */
function найтиЦель(комната, цель) {
  if (цель === undefined || цель === null || цель === '') return null;
  const занятые = занятыеМеста(комната).filter(function (место) {
    return !комната.игроки[место].ушёл;
  });
  const кресло = typeof цель === 'number' ? цель
               : (typeof цель === 'string' && /^\d+$/.test(цель.trim()) ? Number(цель.trim()) : null);
  if (кресло !== null) {
    const место = партии.МЕСТА[кресло - 1];
    return место && занятые.indexOf(место) !== -1 ? место : null;
  }
  if (typeof цель !== 'string') return null;
  const имя = цель.trim();
  for (const место of занятые) {
    if (комната.игроки[место].имя === имя) return место;
  }
  return null;
}

/** Не частит ли человек. Отвечает причиной отказа или пустой строкой. */
function почемуСлишкомЧасто(игрок, поле, пауза, потолок, сейчас) {
  const недавние = (игрок[поле] || []).filter(function (когда) {
    return сейчас - когда < ОКНО_ЗНАКОВ;
  });
  игрок[поле] = недавние;
  const последний = недавние.length ? недавние[недавние.length - 1] : 0;
  if (последний && сейчас - последний < пауза) return 'Слишком часто — подождите пару секунд';
  if (недавние.length >= потолок) return 'Слишком много подряд — сделайте паузу';
  return '';
}

/**
 * Игрок шлёт знак внимания. Отказы объясняем словами: человек должен
 * понимать, почему смайлик не ушёл, — иначе кнопка выглядит сломанной.
 */
function послатьЗнакВнимания(комната, ктоЯ, намерение) {
  const игрок = комната.игроки[ктоЯ];
  if (игрок && игрок.ушёл) {
    return { принято: false, причина: 'Вы вышли из этой партии' };
  }

  const знаки = играКомнаты(комната).знаки;
  const номер = намерение ? намерение.номер : null;
  if (!знаки.этоЗнак(номер)) {
    /* Списка нет вовсе — значит, рядом с новым сервером лежит старая игра.
       Об этом надо сказать отдельно: «такого смайлика нет» увело бы
       разбирательство совсем не туда. */
    if (знаки.сколько() === 0) {
      return { принято: false,
        причина: 'Сервер пока не знает списка эмоций — обновите игру на сервере' };
    }
    return { принято: false, причина: 'Такого смайлика нет' };
  }

  /* Цель. Броску она обязательна: бросок без адресата — это спам без
     адресата. Эмоции и фразы летят на весь стол, у них цели нет, даже
     если игра её прислала. В себя бросать нельзя — иначе тем же спамом
     станет и бросок. */
  const этоБросок = знаки.этоБросок(номер);
  const цель = этоБросок ? найтиЦель(комната, намерение.цель) : null;
  if (этоБросок) {
    if (намерение.цель === undefined || намерение.цель === null || намерение.цель === '') {
      return { принято: false, причина: 'Выберите, в кого бросить' };
    }
    if (!цель) return { принято: false, причина: 'За столом такого игрока нет' };
    if (цель === ктоЯ) return { принято: false, причина: 'В себя бросать нельзя' };
  }

  const сейчас = Date.now();
  const общая = почемуСлишкомЧасто(игрок, 'знаки', ПАУЗА_МЕЖДУ_ЗНАКАМИ, ЗНАКОВ_ЗА_ОКНО, сейчас);
  if (общая) return { принято: false, причина: общая };
  if (этоБросок) {
    const бросковая = почемуСлишкомЧасто(игрок, 'броски', ПАУЗА_МЕЖДУ_БРОСКАМИ, БРОСКОВ_ЗА_ОКНО, сейчас);
    if (бросковая) return { принято: false, причина: бросковая };
    игрок.броски.push(сейчас);
  }

  игрок.знаки.push(сейчас);
  записатьЗнакВнимания(комната, ктоЯ, номер, цель);
  разбудить(комната);
  return { принято: true, знак: номер };
}

function записатьСобытие(комната, ктоЯ, что, имя) {
  const игрок = комната.игроки[ктоЯ];
  комната.событие = {
    кто: ктоЯ,
    что: что,
    имя: имя || (игрок ? игрок.имя : null)
  };
  комната.номерСобытия++;
}

/**
 * Партия кончилась? Тогда комната переходит в «конец» и запоминает,
 * КТО ОСТАЛСЯ ДУРАКОМ: в следующей партии ходят на него. Кто именно
 * будет нападать, комната не решает — это правило игры, и живёт оно
 * в js/game.js («ктоХодитНаДурака»).
 * При ничьей никого не запоминаем, пусть решает младший козырь.
 * В игре парами дураков двое — берём первого по местам, правилу довольно.
 */
function осмотретьПартию(комната) {
  if (комната.этап !== 'игра') return;
  if (!комната.партия || !комната.партия.завершена) return;

  комната.этап = 'конец';
  комната.сыграно++;
  const проигравшие = комната.партия.проигравшие || [];
  комната.дуракПрошлойПартии = проигравшие.length > 0 ? проигравшие[0] : null;
  учестьИтогПартии(комната);
}

/**
 * Статистика: партия кончилась — доиграна или брошена.
 *
 * Считается ровно один раз на партию, за этим следит пометка в комнате.
 * Зовут отовсюду, где партия перестаёт жить: конец по картам, уход
 * соперника, уборка комнаты, пересборка стола, откат входа. Лишний вызов
 * безвреден, пропущенный — потеря партии в счёте, поэтому вызовов больше,
 * чем строго нужно.
 *
 * Доиграна ли партия, видно по «результату»: правила пишут туда слово
 * («ничья» или кто остался в дураках), а уход соперника оставляет пусто —
 * так же это отличает и игра на экране.
 */
function учестьИтогПартии(комната) {
  const партия = комната.партия;
  if (!партия || комната.партияУчтена) return;
  комната.партияУчтена = true;
  const поКартам = партия.завершена === true && typeof партия.результат === 'string';
  статистика.учесть(поКартам ? 'партийДоиграно' : 'партийБрошено');

  /* Рейтинг считаем только по доигранным партиям. Брошенная партия
     (кто-то вышел, стол пересобрали, комнату убрала уборка) силы
     не показывает вовсе — а если бы шла в счёт, самым простым способом
     не проиграть стал бы выход из-за стола перед концом. */
  if (поКартам || ничьяВПартии(партия)) рейтинг.учестьПартию(комната.игра, застольеДляРейтинга(комната));
}

/** Партия кончилась вничью (так бывает в шашках, у дурака — нет). */
function ничьяВПартии(партия) {
  return партия.завершена === true && партия.ничья === true;
}

/**
 * Кто сидел за столом — в том виде, в каком это нужно рейтингу:
 * { номер, имя, этоБот, уровень, победил, ничья }.
 *
 * Номер Telegram есть только у тех, кто открыл игру в мессенджере;
 * остальных рейтинг просто не считает — опознать их нечем. Дальше этого
 * места номера не идут: рейтинг держит их у себя и наружу не отдаёт.
 */
function застольеДляРейтинга(комната) {
  const партия = комната.партия;
  const проигравшие = партия.проигравшие || [];
  const ничья = ничьяВПартии(партия);

  return занятыеМеста(комната).map(function (место) {
    const игрок = комната.игроки[место];
    return {
      номер: игрок.телеграм,
      имя: игрок.имя,
      этоБот: игрок.этоБот === true,
      уровень: игрок.уровень || комната.уровеньБотов,
      /* Победил — это «партия доиграна и он не среди проигравших».
         У дурака проигравший один (дурак), у шашек — сторона, потерявшая
         ход или шашки; в обоих случаях правила уже всё посчитали. */
      победил: !ничья && партия.завершена === true && проигравшие.indexOf(место) === -1,
      ничья: ничья
    };
  });
}

/**
 * Убрать из-за стола тех, кто ушёл насовсем.
 *
 * Зачем это нужно перед раздачей. Ушедший в конце партии остаётся числиться
 * за своим местом (по его пропуску ему ещё показывают итог), и без этой
 * уборки на реванше ему бы раздали карты — а ходить за него некому.
 * Партия встала бы намертво на первом же его ходе.
 *
 * Ботов это не касается: бот за столом остаётся, даже если он занял место
 * ушедшего посреди партии, — за него ходит сервер.
 */
function убратьУшедших(комната) {
  for (const место of занятыеМеста(комната)) {
    const игрок = комната.игроки[место];
    if (игрок.этоБот || !игрок.ушёл) continue;
    /* Место освобождаем всегда — за столом должны сидеть те, кто играет.
       Но если человек не прощался, а просто замолчал, пропуск его помним:
       вернётся, пока комната жива, — сядет обратно, а не улетит на стартовый
       экран с «комнаты нет». */
    запомнитьДляВозврата(комната, игрок);
    delete комната.игроки[место];
  }
  if (!комната.игроки[комната.хозяин]) передатьХозяина(комната);
}

/** Раздать карты всем, кто сидит за столом, и начать партию. */
function раздатьПартию(комната, ктоНачинает) {
  убратьУшедших(комната);
  const места = занятыеМеста(комната);
  /* Раздаёт сама игра: комната не знает, что она раздаёт — карты, шашки
     или что-то третье. Настройки стола складываем не разбирая; лишнее
     игра просто не заметит. */
  комната.партия = играКомнаты(комната).раздать(ктоНачинает, {
    игроки: места,
    переводной: комната.переводной,
    парами: комната.парами,
    сложность: комната.уровеньБотов
  });
  комната.этап = 'игра';
  for (const место of места) {
    const игрок = комната.игроки[место];
    if (игрок && !игрок.этоБот) игрок.хочетЕщё = false;
  }
  познакомитьЗастолье(комната, места);
  учестьРаздачу(комната, места);
}

/**
 * Статистика: партия началась. Что за стол — с ботами или из одних людей,
 * парный или нет — известно ровно в миг раздачи, поэтому считается здесь.
 * Итог этой партии (доиграна или брошена) ещё не известен — за ним
 * следит учестьИтогПартии.
 */
function учестьРаздачу(комната, места) {
  комната.партияУчтена = false;
  статистика.учесть('партийНачато');
  const естьБот = места.some(function (место) {
    const игрок = комната.игроки[место];
    return Boolean(игрок && игрок.этоБот);
  });
  статистика.учесть(естьБот ? 'партийСБотами' : 'партийСЛюдьми');
  if (комната.парами) статистика.учесть('партийПарами');
}

/**
 * Запомнить, что эти люди играли за одним столом.
 *
 * Делается это в миг раздачи карт, а не после партии, и так надёжнее:
 * за столом люди уже сидят, а доиграть могут и не успеть — кто-то выйдет,
 * у кого-то сядет телефон. Знакомство от этого не становится неправдой.
 *
 * Боты и те, кто открыл игру не в Telegram, сюда не попадают: у первых
 * номера нет вовсе, у вторых его неоткуда взять.
 */
function познакомитьЗастолье(комната, места) {
  const люди = [];
  for (const место of места) {
    const игрок = комната.игроки[место];
    if (!игрок || игрок.этоБот || !игрок.телеграм) continue;
    люди.push({ номер: игрок.телеграм, имя: игрок.имя });
  }
  if (люди.length < 2) return;
  знакомые.запомнитьЗастолье(люди);
}

/**
 * Кто из этих людей сейчас за столом. Отвечаем по живым комнатам и только
 * про тех, о ком спросили: перебирать всех играющих и отдавать их наружу
 * нельзя — это превратило бы список знакомых в список всех подряд.
 *
 * «За столом» значит именно это: человек сидит в комнате на нашем сервере
 * и не пропал со связи. Открыт ли у него Telegram, мы не знаем и знать
 * не можем — и обещать этого не должны.
 */
function ктоСейчасЗаСтолом(номера) {
  const ищем = new Set((номера || []).filter(function (номер) {
    return Number.isInteger(номер) && номер > 0;
  }));
  const нашлись = new Set();
  if (!ищем.size) return нашлись;

  for (const комната of комнаты.values()) {
    for (const место of местаКомнаты(комната)) {
      const игрок = комната.игроки[место];
      if (!игрок || игрок.этоБот || игрок.ушёл || !игрок.наСвязи) continue;
      if (игрок.телеграм && ищем.has(игрок.телеграм)) нашлись.add(игрок.телеграм);
    }
  }
  return нашлись;
}

/**
 * Ход игрока: правила проверяют, комната запоминает событие и будит
 * остальных. Отказ никого не будит — он касается только того,
 * кто ошибся.
 *
 * Часть действий про карты вовсе не знает: «начать», «сыграть ещё»,
 * настройки стола и боты — это дела комнаты, и разбираются они здесь же,
 * до того как слово переходит правилам.
 */
function сделатьХод(комната, ктоЯ, намерение) {
  отметитьЖизнь(комната, ктоЯ);

  const действие = намерение && typeof намерение.действие === 'string' ? намерение.действие : '';

  switch (действие) {
    case 'ещё':         return предложитьЕщё(комната, ктоЯ);
    case 'пересобрать': return пересобратьСтол(комната, ктоЯ);
    case 'начать':      return начатьПоКнопке(комната, ктоЯ);
    case 'настройки':   return поменятьНастройкиКомнаты(комната, ктоЯ, намерение);
    case 'бот':         return посадитьБота(комната, ктоЯ, намерение);
    /* Знак внимания можно послать в любую минуту — и в прихожей, и посреди
       партии, и после неё: «Привет!» перед раздачей и «Хорошая игра» после
       неё нужны не меньше, чем «Ходи!» в середине. */
    case 'эмоция':      return послатьЗнакВнимания(комната, ктоЯ, намерение);
    case 'пересадить':  return пересадить(комната, ктоЯ, намерение);
    /* «В напарники» — то же перемещение, но просит его игрок про себя,
       поэтому и дверь своя: право у неё другое (см. сделатьНапарником). */
    case 'в-напарники': return сделатьНапарником(комната, ктоЯ, намерение);
    case 'убрать-бота': return убратьБота(комната, ктоЯ);
    default: break;
  }

  if (комната.этап === 'ожидание') {
    return {
      принято: false,
      причина: комната.компания
        ? 'Партия ещё не началась: ждём, когда хозяин комнаты нажмёт «Начать»'
        : 'Соперник ещё не пришёл'
    };
  }

  /* Пропуск ушедшего продолжает работать — по нему ему показывают итог.
     Но ходить он уже не может: за столом на его месте либо никого нет,
     либо доигрывает бот, и два игрока на одном месте — это путаница. */
  const я = комната.игроки[ктоЯ];
  if (я && я.ушёл) {
    return { принято: false, причина: 'Вы вышли из этой партии — ходить в ней больше нельзя' };
  }

  const ответ = играКомнаты(комната).сделатьХод(комната.партия, ктоЯ, намерение);
  if (!ответ.принято) {
    /* Отказ тоже проверяет насос ботов, и это не перестраховка: как только
       появится ход вне очереди, путь «ход отклонён» может оказаться дорогой,
       по которой комната уходит в вечное молчание — таймера нет, а завести
       его некому (длинный опрос насос не заводит, уборщик не трогает того,
       кто висит на опросе).

       Но ПЕРЕЗАВОДИТЬ насос здесь нельзя, только поднимать уснувший.
       Партия от отказа не изменилась, значит и заведённый будильник верен.
       А перезавод сначала гасит прежний будильник и лишь потом заводит
       новый на семь десятых секунды — и тот, кто присылает отказные ходы
       чаще этого срока, гасит будильник вечно. Замерено: 61 отказ за
       14 секунд — ботов сходило ноль, стол стоял, пока палец не убрали.
       Причём стоял он для ВСЕХ за столом, а не только для нажимавшего. */
    поднятьУснувшийНасос(комната);
    return ответ;
  }

  /* Событие приписываем не тому, кто нажал кнопку, а тому, с кем оно
     случилось. Разница видна на одном случае: подход заканчивает
     подкидывающий, а карты со стола забирает отбивавшийся. */
  записатьСобытие(комната, ответ.ктоСделал || ктоЯ, ответ.событие);
  /* Дальше это поле не нужно, а игроку его показывать нельзя: «ктоСделал» —
     внутреннее имя места за столом (вроде «бот-3»). Убираем сразу, чтобы оно
     физически не могло уехать наружу вместе с ответом. */
  delete ответ.ктоСделал;
  осмотретьПартию(комната);
  разбудить(комната);
  ботыДумают(комната);
  return ответ;
}

/* ---------------------------------------------------------------------
   Прихожая: пока карты не розданы, комнатой распоряжается создатель
   --------------------------------------------------------------------- */

/**
 * Общая проверка для всех действий прихожей: распоряжаться столом может
 * только хозяин комнаты и только пока партия не началась.
 * Вернёт отказ или null, если всё в порядке.
 */
function можноРаспоряжаться(комната, ктоЯ) {
  if (комната.этап === 'игра') {
    return { принято: false, причина: 'Партия уже идёт — стол теперь не поменять' };
  }
  if (комната.этап === 'конец') {
    return {
      принято: false,
      причина: 'Эта партия закончена. Нажмите «Сыграть ещё» — стол останется прежним'
    };
  }
  if (ктоЯ !== комната.хозяин) {
    return { принято: false, причина: 'Стол собирает тот, кто создал комнату' };
  }
  return null;
}

/* Пометка «комната.компания = true» ниже ставится в тех действиях прихожей,
   которыми стол собирают впервые, и вот почему. Пока хозяин ничего не трогал,
   комната остаётся прежней комнатой на двоих: друг вошёл — карты розданы сами,
   как было всегда. Но раз стол собрали руками (поменяли правила, посадили
   бота, нажали «Начать»), сама собой партия начинаться уже не должна — её
   начинает человек. Обратной дороги нет, да она и не нужна.

   В «убрать бота» пометки нет нарочно: убирать там нечего, пока бота не
   посадили, а посадка её уже поставила. Ставить пометку ещё и здесь значило
   бы менять комнату при нажатии, которое ничего не сделало. */

/** Хозяин поменял правила игры или число мест за столом. */
function поменятьНастройкиКомнаты(комната, ктоЯ, намерение) {
  const нельзя = можноРаспоряжаться(комната, ктоЯ);
  if (нельзя) return нельзя;

  if (!применитьНастройки(комната, намерение)) {
    return { принято: false, причина: 'Не понял, что именно поменять за столом' };
  }
  комната.компания = true;
  записатьСобытие(комната, ктоЯ, 'настройки');
  разбудить(комната);
  return { принято: true, событие: 'настройки' };
}

/**
 * Можно ли раздвинуть стол на одно место ради нового бота.
 *
 * Раздвигаем только в одном случае: человек ни разу не называл число мест,
 * то есть за столом стоит начальная двойка — не выбор, а то, с чего комната
 * начинается. Тогда «Посадить бота» в обычной игре вдвоём работает как
 * раньше: стол растёт под компанию сам.
 *
 * Как только число мест названо (выбрали «Сколько игроков за столом» или
 * включили игру парами), оно становится законом. Раньше стол раздвигался
 * всегда, и выходило вот что: человек выбрал стол на четверых, нажал
 * «Посадить бота» лишний раз — и молча получил пятерых, а потом шестерых.
 * В парной игре это ломало партию совсем: начать вчетвером уже нельзя,
 * а виноватым выглядит игрок, который ничего, кроме числа ботов, не менял.
 */
function можноРаздвинутьСтол(комната) {
  if (комната.местВыбрали) return false;              // выбранное число мест не трогаем
  if (комната.парами) return false;                   // парная игра бывает только вчетвером
  return комната.мест < пределыМест(комната).макс;
}

/**
 * Почему бот не сел — человеческими словами, с подсказкой, что делать.
 * Причина всегда одна (мест нет), а вот выход из положения разный,
 * поэтому и говорим по-разному.
 */
function почемуБотуНекудаСесть(комната) {
  if (комната.парами) {
    return 'Игра парами бывает только вчетвером, и все четыре места уже заняты. ' +
      'Хотите играть большим кругом — сначала выключите игру парами';
  }
  if (комната.мест >= пределыМест(комната).макс) {
    return 'За столом нет свободных мест: больше шестерых не садится';
  }
  return 'Свободных мест нет: за столом их ' + комната.мест +
    ', столько вы и выбрали. Хотите играть большим кругом — ' +
    'поменяйте «Сколько игроков за столом»';
}

/** Посадить на свободное место бота. */
function посадитьБота(комната, ктоЯ, намерение) {
  const нельзя = можноРаспоряжаться(комната, ктоЯ);
  if (нельзя) return нельзя;

  комната.компания = true;
  if (!свободноеМесто(комната) && можноРаздвинутьСтол(комната)) комната.мест++;

  const место = свободноеМесто(комната);
  if (!место) {
    return { принято: false, причина: почемуБотуНекудаСесть(комната) };
  }

  /* Уровень отдельного бота проверяем тем же списком: сюда приходит третья
     дорога к тому же полю, и без проверки любая строка легла бы боту в память
     и досталась правилам вместо уровня. Не назвали или назвали непонятное —
     бот играет так же, как весь стол. */
  const уровень = уровеньИзСписка(намерение.уровень) || комната.уровеньБотов;
  комната.игроки[место] = новыйБот(место, уровень);
  записатьСобытие(комната, ктоЯ, 'посадили-бота');
  разбудить(комната);
  return { принято: true, событие: 'посадили-бота' };
}

/** Убрать из-за стола последнего посаженного бота. */
function убратьБота(комната, ктоЯ) {
  const нельзя = можноРаспоряжаться(комната, ктоЯ);
  if (нельзя) return нельзя;

  const боты = занятыеМеста(комната).filter(function (место) {
    return комната.игроки[место].этоБот;
  });
  if (боты.length === 0) {
    return { принято: false, причина: 'За столом нет ни одного бота' };
  }

  delete комната.игроки[боты[боты.length - 1]];

  /* Стол, который раздвинулся сам, сам же и ужимается. Иначе получалось
     обидное: посадил бота — «играют трое», убрал его — по-прежнему «играют
     трое», только одно место пустое, и человек не понимает, что он сделал.
     Стол, число мест которого человек назвал сам, не трогаем: пустое место
     там оставлено нарочно — под друга, который вот-вот войдёт. */
  if (!комната.местВыбрали) {
    комната.мест = Math.max(пределыМест(комната).мин, докудаЗанятСтол(комната));
  }

  записатьСобытие(комната, ктоЯ, 'убрали-бота');
  разбудить(комната);
  return { принято: true, событие: 'убрали-бота' };
}

/**
 * Почему парная игра сейчас не начнётся — и что делать.
 *
 * Совет обязан зависеть от того, много за столом народу или мало. Раньше
 * он был один на оба случая («Посадите ботов или выключите игру парами»),
 * и при пятерых за столом получалась насмешка: чтобы играть вчетвером,
 * человеку предлагали посадить ещё одного.
 */
function чтоНеТакДляПарнойИгры(комната, занято) {
  const начало = 'Игра парами бывает только вчетвером, а за столом ' + занято.length + '. ';

  if (занято.length < пределыМест(комната).впарах) {
    return начало + 'Позовите друга по коду или посадите бота — или выключите игру парами';
  }

  /* Народу больше четырёх. Убрать лишнего можно только если это бот:
     выгнать человека из-за стола хозяин не может, у него такой кнопки нет.
     Поэтому людям за столом честно советуем другое — выключить игру парами. */
  const естьБоты = занято.some(function (место) { return комната.игроки[место].этоБот; });
  return начало + (естьБоты
    ? 'Уберите лишнего бота или выключите игру парами'
    : 'Выключите игру парами — или пусть кто-то один выйдет из комнаты');
}

/**
 * «Начать» — карты раздаются. Кнопка есть только у хозяина комнаты:
 * ему видно, все ли друзья уже подошли, а серверу — нет.
 */
function начатьПоКнопке(комната, ктоЯ) {
  const нельзя = можноРаспоряжаться(комната, ктоЯ);
  if (нельзя) return нельзя;

  const занято = занятыеМеста(комната);
  if (занято.length < пределыМест(комната).мин) {
    return {
      принято: false,
      причина: 'За столом пока только вы. Позовите друга по коду или посадите бота'
    };
  }
  /* Парная игра бывает только вчетвером. Молча превращать её в обычную
     нечестно: человек выбирал одно, а получил бы другое, — поэтому
     говорим прямо и даём поправить. */
  if (комната.парами && занято.length !== пределыМест(комната).впарах) {
    return { принято: false, причина: чтоНеТакДляПарнойИгры(комната, занято) };
  }

  комната.компания = true;
  раздатьПартию(комната, null);
  записатьСобытие(комната, ктоЯ, 'начали');
  разбудить(комната);
  ботыДумают(комната);
  return { принято: true, событие: 'начали' };
}

/* ---------------------------------------------------------------------
   Боты ходят на сервере
   --------------------------------------------------------------------- */

/** Отменить отложенный ход бота, если он был назначен. */
function отменитьХодБота(комната) {
  комната.планБота = null;
  if (!комната.таймерБота) return;
  clearTimeout(комната.таймерБота);
  комната.таймерБота = null;
}

/** На каком уровне играет это место — или null, если там человек. */
function уровеньБота(комната, имя) {
  const игрок = комната.игроки[имя];
  if (!игрок || !игрок.этоБот) return null;
  return игрок.уровень || комната.уровеньБотов;
}

/**
 * Если очередь дошла до бота — назначить его ход через небольшую паузу.
 *
 * Пауза нужна для людей: карты, падающие на стол мгновенно и все разом,
 * читаются как «что-то произошло, а что — непонятно». За эти доли секунды
 * игрок успевает увидеть каждый ход отдельно.
 *
 * Ход бота делается ЗДЕСЬ, на сервере, а не в чьём-то браузере. Иначе
 * картина у игроков разошлась бы: у одного бот уже сходил, у другого ещё
 * нет, а если «ведущий» потеряет связь — партия встанет навсегда.
 */
function ботыДумают(комната) {
  отменитьХодБота(комната);
  if (комната.этап !== 'игра') return;

  /* Два повода завести таймер, но таймер всегда ОДИН на комнату.
     Первый — очередь дошла до бота: обычный ход через короткую паузу.
     Второй — очередь не у бота, но кто-то из ботов может бросить заходную
     вне очереди: бросок через длинную паузу, чтобы человек успевал первым.
     Ход в свою очередь важнее броска: бот в свой ход и так подкинет. */
  const игра = играКомнаты(комната);
  const место = игра.чейХод(комната.партия);
  const игрок = место ? комната.игроки[место] : null;
  if (игрок && игрок.этоБот) {
    завестиТаймерБота(комната, игра.темпБота.обычный, function () {
      сходитьЗаБота(комната, место);
    });
    return;
  }

  /* Ход вне очереди бывает не у всякой игры: у дурака это подхват заходной,
     а в шашках ходят строго по очереди, и спрашивать не о чем. Игра, у
     которой такого хода нет, кладёт сюда null — и насос просто не ищет
     второго повода сходить. */
  if (!игра.ходВнеОчереди) return;

  /* План броска решается ЗДЕСЬ и запоминается вместе с таймером. При
     срабатывании ничего не переспрашивается: если бы план решался дважды,
     таймер, заведённый на «да», при срабатывании мог бы получить «нет»,
     выйти ни с чем — и завести следующий таймер стало бы некому. */
  const план = игра.ходВнеОчереди.ктоСходит(комната.партия, function (имя) {
    return уровеньБота(комната, имя);
  });
  if (!план) return;
  комната.планБота = план;
  завестиТаймерБота(комната, игра.темпБота.внеОчереди, function () {
    const задуманное = комната.планБота;
    комната.планБота = null;
    подхватитьЗаБота(комната, задуманное);
  });
}

/** Единственное место, где заводится таймер бота: один и не держит программу. */
function завестиТаймерБота(комната, пауза, дело) {
  комната.таймерБота = setTimeout(function () {
    комната.таймерБота = null;
    дело();
  }, пауза);
  // Таймер не должен держать программу запущенной — как и у уборщика.
  if (комната.таймерБота.unref) комната.таймерБота.unref();
}

/**
 * Бросок заходной за бота — по запомненному плану.
 *
 * Не вышло (человек успел раньше, стол упёрся в потолок, карта в руке
 * сдвинулась) — проваливаемся вниз В ТОМ ЖЕ ТАКТЕ: если очередь за ботом,
 * он ходит обычным ходом прямо сейчас, без новой паузы. Отдельный «пустой»
 * заход через паузу — это карусель по три секунды без единого хода; такой
 * шрам в этом файле уже описан у сходитьЗаБота. Если и ходить некому —
 * перепланировать один раз: насос сам разберётся, есть ли повод.
 */
function подхватитьЗаБота(комната, план) {
  if (комната.этап !== 'игра' || !план) return;
  const игра = играКомнаты(комната);
  const игрок = комната.игроки[план.кто];
  const сделано = игрок && игрок.этоБот && игра.ходВнеОчереди
    ? игра.ходВнеОчереди.сходить(комната.партия, план.кто, план.карта)
    : null;

  if (!сделано) {
    const теперь = игра.чейХод(комната.партия);
    const тот = теперь ? комната.игроки[теперь] : null;
    if (тот && тот.этоБот) {
      сходитьЗаБота(комната, теперь);   // она перезаведёт насос сама
      return;
    }
    ботыДумают(комната);
    return;
  }

  записатьСобытие(комната, сделано.ктоСделал, сделано.событие);
  осмотретьПартию(комната);
  разбудить(комната);
  ботыДумают(комната);   // партия изменилась — перезавод по праву
}

/** Один ход бота: сходить, рассказать всем и посмотреть, чья очередь дальше. */
function сходитьЗаБота(комната, место) {
  const игрок = комната.игроки[место];
  if (!игрок || !игрок.этоБот) return;
  if (комната.этап !== 'игра') return;

  const игра = играКомнаты(комната);
  let сделано = игра.ходЗаБота(комната.партия, место, игрок.уровень);
  let ходил = место;

  /* Не вышло — значит, пока таймер ждал, очередь ушла к другому. Тогда
     пробуем сходить за того, чья очередь СЕЙЧАС, и делаем это в том же
     такте, без новой паузы.

     Почему не «завести таймер и попробовать снова». Проверено на этом же
     файле: отдельный «пустой» ход через паузу превращается в карусель по
     семь десятых секунды без конца — насос крутится, ходов нет, а со
     стороны партия выглядит зависшей.

     Если и запасной ход не вышел, ниже остаётся единственный перезавод
     насоса: он сам разберётся, надо ли кого-то будить. */
  if (!сделано) {
    const теперь = игра.чейХод(комната.партия);
    const другой = теперь && теперь !== место ? комната.игроки[теперь] : null;
    if (другой && другой.этоБот && !другой.ушёл) {
      сделано = игра.ходЗаБота(комната.партия, теперь, другой.уровень);
      ходил = теперь;
    }
  }

  if (!сделано) {
    ботыДумают(комната);
    /* Насос перезавели, а ходить всё равно некому, хотя очередь за ботом, —
       вот это уже невозможное. Пишем в консоль: молчаливое зависание ищут
       неделю, а строчку видно сразу. Игру при этом не роняем: сторож
       в уборщике поднимет комнату через несколько секунд. */
    const ктоТеперь = игра.чейХод(комната.партия);
    const тотИгрок = ктоТеперь ? комната.игроки[ктоТеперь] : null;
    if (!комната.таймерБота && тотИгрок && тотИгрок.этоБот) {
      console.warn('Насос ботов: ход за ботом, а сходить не вышло. Комната ' + комната.код);
    }
    return;
  }

  // Как и у живого игрока: карты со стола мог забрать не тот бот, что ходил.
  записатьСобытие(комната, сделано.ктоСделал || ходил, сделано.событие);
  /* Бот тоже иногда отвечает смайликом. Дорога у него ровно та же, что
     у человека, и сервер их не различает: правила вернули номер вместе
     с ходом — записываем. КОГДА боту вздумается ответить, решают сами
     правила (js/game.js), сервер в это не лезет. */
  /* Правила могут вернуть и голый номер, и { номер, цель } — бросок в кого-то.
     Разбирает это партия; здесь только пишем то, что она разрешила. */
  const голос = игра.знаки.голосБота(сделано);
  if (голос) {
    записатьЗнакВнимания(комната, ходил, голос.номер,
                         голос.цель && голос.цель !== ходил ? найтиЦель(комната, партии.номерМеста(голос.цель)) : null);
  }
  осмотретьПартию(комната);
  разбудить(комната);
  ботыДумают(комната);   // за ботом может ходить другой бот
}

/**
 * Реванш. Каждый нажавший просто предлагает; как только согласились все,
 * кто ещё за столом, карты раздаются заново в той же комнате, с тем же
 * кодом и теми же пропусками. Отказ отдельной кнопкой не нужен:
 * кто не хочет играть, тот выходит, и остальные это увидят.
 *
 * Боты согласны всегда — спрашивать их не о чем.
 *
 * Нажали второй раз — остальных не тревожим. Пропуск после конца партии
 * работает, а кнопку человек легко жмёт дважды: нетерпеливый палец, ответ
 * не дошёл, страница повторила запрос. Раньше каждое такое нажатие писало
 * событие заново, и остальные читали «Пётр предложил сыграть ещё» два-три
 * раза подряд — а заодно это был бесплатный способ гонять сервер по кругу.
 *
 * Но пересчёт «согласны ли уже все» делается в любом случае, и это важно:
 * пока Пётр ждал, кто-то мог выйти из-за стола, и теперь согласия остальных
 * ждать больше не от кого. Пропусти мы пересчёт — реванш не собрался бы
 * никогда, а виноватым выглядел бы тот, кто просто нажал ещё раз.
 */
function предложитьЕщё(комната, ктоЯ) {
  if (комната.этап !== 'конец') {
    return { принято: false, причина: 'Партия ещё не закончена' };
  }

  const я = комната.игроки[ктоЯ];

  /* Сам уже вышел — звать некого и не за чем. Пропуск после выхода
     продолжает работать, и без этой проверки вышедший мог позвать на реванш:
     оставшийся видел бы «Друг зовёт сыграть ещё», а нажать не смог бы —
     ему бы ответили, что соперник вышел. */
  if (!я || я.ушёл) {
    return { принято: false, причина: 'Вы вышли из этой партии — чтобы сыграть ещё, начните новую' };
  }

  /* Остальные за столом — все, кроме меня и кроме ушедших людей.
     Бот считается сидящим всегда, даже если он занял место ушедшего:
     доиграть партию с ботами можно, а вот звать ушедшего человека — нет. */
  const остальные = занятыеМеста(комната)
    .filter(function (место) {
      if (место === ктоЯ) return false;
      const игрок = комната.игроки[место];
      return игрок.этоБот || !игрок.ушёл;
    })
    .map(function (место) { return комната.игроки[место]; });

  if (остальные.length === 0) {
    return { принято: false, причина: 'Соперник вышел из игры' };
  }

  const ужеЗвал = я.хочетЕщё === true;
  я.хочетЕщё = true;

  const ждёмОтвета = остальные.filter(function (игрок) { return !игрок.хочетЕщё; });
  if (ждёмОтвета.length > 0) {
    /* Отвечаем как в первый раз — «зовёт». Отказ тут был бы неправдой:
       человек и правда зовёт играть дальше, просто остальные пока молчат. */
    if (ужеЗвал) return { принято: true, событие: 'зовёт' };
    // Ждём согласия остальных — пока это только предложение.
    записатьСобытие(комната, ктоЯ, 'зовёт');
    разбудить(комната);
    return { принято: true, событие: 'зовёт' };
  }

  // Согласны все — раздаём заново.
  раздатьПартию(комната, комната.дуракПрошлойПартии);
  записатьСобытие(комната, ктоЯ, 'реванш');
  разбудить(комната);
  ботыДумают(комната);
  return { принято: true, событие: 'реванш' };
}

/**
 * «Пересобрать стол» — вернуть всех в прихожую, не создавая новой комнаты.
 *
 * Зачем это нужно. Раньше комната после первой раздачи в прихожую
 * не возвращалась никогда, и компания оказывалась заперта втроём бедами:
 *
 *   — бот, занявший место ушедшего, оставался за столом навсегда: убрать
 *     его можно только в прихожей, а попасть туда было уже нельзя. Стол
 *     партия за партией превращался в ботов;
 *   — друг, опоздавший к началу, не входил никогда: дверь по коду открыта
 *     только в прихожей;
 *   — «переводной», «парами» и число мест между партиями не менялись ни у кого.
 *
 * Выход был один — создавать новую комнату и заново диктовать всем новый код.
 *
 * Кнопка эта хозяйская и только после конца партии: возвращать людей
 * в прихожую посреди раздачи значило бы бросить их карты на полуслове.
 *
 * Дальше всё делается само: страница видит этап «ожидание» и показывает
 * прихожую — ту же самую, с которой комната начиналась.
 */
function пересобратьСтол(комната, ктоЯ) {
  if (комната.этап === 'ожидание') {
    return { принято: false, причина: 'Карты ещё не розданы — стол и так можно собирать' };
  }
  if (комната.этап !== 'конец') {
    return { принято: false, причина: 'Партия ещё идёт — стол пересоберём, когда она закончится' };
  }

  const я = комната.игроки[ктоЯ];
  if (!я || я.ушёл) {
    return { принято: false, причина: 'Вы вышли из этой партии — чтобы играть дальше, начните новую' };
  }
  if (ктоЯ !== комната.хозяин) {
    return { принято: false, причина: 'Стол собирает тот, кто создал комнату' };
  }

  убратьУшедших(комната);     // попрощавшихся за столом больше нет, места свободны
  отменитьХодБота(комната);   // отложенным ходам в комнате без партии ходить некуда
  учестьИтогПартии(комната);  // обычно уже учтена по картам — это страховка
  комната.партия = null;
  комната.этап = 'ожидание';
  /* Пометку «это компания» ставим обязательно: без неё прихожую не увидит
     никто, а комната на двоих раздала бы карты сама, едва войдёт друг. */
  комната.компания = true;
  комната.дуракПрошлойПартии = null;   // партии, к которой это относилось, больше нет

  /* «Хочу ещё» сбрасываем только людям — ровно как при раздаче. Боту это
     согласие менять нельзя: он согласен всегда, и без его молчаливого «да»
     реванш после следующей партии не собрался бы уже никогда. */
  for (const место of занятыеМеста(комната)) {
    const игрок = комната.игроки[место];
    if (!игрок.этоБот) игрок.хочетЕщё = false;
  }

  записатьСобытие(комната, ктоЯ, 'пересобрали');
  разбудить(комната);
  return { принято: true, событие: 'пересобрали' };
}

/* ---------------------------------------------------------------------
   Уход и уборка
   --------------------------------------------------------------------- */

/**
 * Игрок сам вышел. Это не то же самое, что потеря связи: пропавшего партия
 * ждёт, и он может вернуться, а ушедшего ждать незачем — иначе остальные
 * будут бесконечно ждать хода того, кого уже нет.
 *
 * Что происходит дальше, зависит от того, сколько человек за столом:
 *
 *   — карты ещё не розданы: место просто освобождается, на него может сесть
 *     кто-то другой. Ушёл хозяин — комнатой распоряжается следующий;
 *   — за столом двое: партия заканчивается без победителя, как и раньше.
 *     Ни выигрыша, ни поражения тут нет — просто несостоявшаяся игра;
 *   — за столом трое и больше: место ушедшего занимает бот и доигрывает
 *     его картами. Так партия у остальных не рушится из-за одного человека,
 *     а сдавать его карты в отбой посреди подхода было бы нечестно
 *     к тем, кто на них рассчитывал.
 *
 * Второй раз выйти нельзя — и вот почему это важно. Пропуск после выхода
 * продолжает работать (по нему ушедшему ещё показывают итог), а запрос
 * «выйти» страница легко шлёт дважды: человек нажал кнопку и закрыл вкладку,
 * или ответ не дошёл и браузер повторил. Без этой проверки второй запрос
 * проходил целиком, и остальные читали «Пётр вышел из игры — за него
 * доигрывает бот» два раза подряд.
 *
 * Тому, кто прислал запрос дважды, отвечаем как в первый раз — «вышел»
 * (сервер так и отвечает: эта функция ответа не возвращает вовсе). Отказ
 * тут был бы неправдой: человека за столом и правда больше нет, а страница,
 * повторившая запрос после обрыва связи, показала бы ошибку на ровном месте.
 *
 * Третий довод — «заМолчание». Так эта же дверь служит двум разным случаям:
 * человек нажал «Выйти» (довода нет) или его вывела уборка за три минуты
 * тишины (довод есть). Наружу разница не видна вовсе — остальные и там,
 * и там читают одно и то же, — но вернуться за стол по своему пропуску
 * может только второй (см. вернутьЗаСтол).
 */
function выйти(комната, ктоЯ, заМолчание) {
  const игрок = комната.игроки[ктоЯ];
  if (!игрок) return;
  if (игрок.ушёл) return;   // он уже вышел: второй раз рассказывать об этом нечего
  игрок.ушёл = true;
  игрок.выбылЗаМолчание = заМолчание === true;
  игрок.наСвязи = false;
  игрок.хочетЕщё = false;   // ушедший никого уже не зовёт играть дальше
  комната.трогали = Date.now();

  if (комната.этап === 'ожидание') {
    // Пропал из прихожей молча — место освобождаем, но человека ждём обратно.
    запомнитьДляВозврата(комната, игрок);
    delete комната.игроки[ктоЯ];
    /* Имя называем прямо здесь: в комнате этого человека уже нет, а рассказ
       о его уходе остальные соберут позже — искать имя будет негде. */
    if (комната.компания) записатьСобытие(комната, ктоЯ, 'ушёл-из-комнаты', игрок.имя);
  } else if (комната.партия && !комната.партия.завершена) {
    if (комната.партия.игроки.length > пределыМест(комната).мин) {
      игрок.этоБот = true;
      игрок.уровень = комната.уровеньБотов;
      /* Имя человека оставляем как есть. Раньше место переименовывалось
         в «Бот 2», и со стороны выглядело так, будто Пётр исчез, а вместо
         него из ниоткуда появился какой-то бот. На самом деле карты Петра
         никуда не делись — их просто доигрывает бот, и это ровно то, что
         должно быть видно: имя «Пётр», роль «бот», пометка «вышел». */
      игрок.хочетЕщё = true;              // бот всегда согласен играть дальше
      записатьСобытие(комната, ктоЯ, 'ушёл-бот');
    } else {
      /* Заканчиваем партию без победителя. Поле «результат» намеренно
         оставляем пустым — по нему клиент и поймёт, что дело не в картах. */
      комната.партия.завершена = true;
      комната.партия.результат = null;
      комната.партия.проигравшие = [];
      комната.этап = 'конец';
      учестьИтогПартии(комната);   // брошена: до конца по картам не дошла
      записатьСобытие(комната, ктоЯ, 'ушёл');
    }
  }

  /* Звание хозяина уходит живому человеку — где бы ни застал уход: и в
     прихожей, и посреди партии, и после её конца. Одно место на все случаи
     нарочно: раньше звание передавали только в прихожей, и вышедший посреди
     партии оставался хозяином навсегда. Его место к тому времени занимал бот,
     а бота уборка ушедших не трогает — значит, и повода передать звание
     больше не возникало никогда. Стол оставался без хозяина: распорядиться
     им не мог уже никто. */
  if (ктоЯ === комната.хозяин) передатьХозяина(комната);

  разбудить(комната);
  ботыДумают(комната);   // если ход был за ушедшим, теперь сходит бот

  /* Живых людей не осталось — держать комнату незачем. Кроме одного стола:
     того, что открыт из группового чата и ещё ждёт первого игрока. Он для
     того и открыт, чтобы стоять пустым: в чате висит кнопка «Сесть за стол»,
     и один случайно заглянувший, который тут же передумал, не должен уносить
     стол с собой у всего чата. Такой стол закроет уборщик по своему сроку
     (см. срокЖизни) — или он дождётся людей и станет обычной комнатой. */
  if (людиЗаСтолом(комната).length === 0 && !ждётПервого(комната)) {
    удалитьКомнату(комната.код);
  }
}

/**
 * Это стол из чата, который ещё ни разу не сыграл и стоит пустым?
 * Считаем по числу сыгранных партий, а не по одному этапу: компания,
 * вернувшаяся в прихожую после партии, — это уже обычный живой стол,
 * и опустеть насовсем ему можно.
 */
function ждётПервого(комната) {
  return комната.безХозяина === true &&
         комната.этап === 'ожидание' &&
         комната.сыграно === 0;
}

/**
 * Хозяин ушёл — распоряжаться столом становится кто-то из оставшихся.
 * Иначе комната зависла бы навсегда: начать партию некому, а сидящие
 * ждали бы кнопки, которой ни у кого нет.
 *
 * Звание достаётся живому человеку, и только ему: бот кнопку не нажмёт,
 * а ушедший к ней уже не вернётся.
 *
 * Из живых выбираем того, кто СЕЙЧАС на связи, а среди таких — того, кто
 * сидит ближе к началу стола (он же обычно и вошёл раньше). Связь тут
 * важнее старшинства: у человека, который отошёл или потерял интернет,
 * звание пролежало бы мёртвым грузом, и остальные всё это время не могли
 * бы ни поменять правила, ни начать партию. Если на связи нет никого,
 * отдаём звание первому живому: он, скорее всего, вот-вот вернётся.
 *
 * Совсем никого живого — ставим первое место просто чтобы поле не осталось
 * пустым: такая комната тут же закрывается, распоряжаться в ней нечем.
 */
function передатьХозяина(комната) {
  const люди = людиЗаСтолом(комната);
  // За столом без хозяина некому передать — ждём следующего вошедшего.
  const некому = комната.безХозяина ? null : партии.ПЕРВЫЙ;
  комната.хозяин = людиНаСвязи(комната)[0] || люди[0] || некому;
}

/**
 * Что со столом — для бота, который открыл его из чата и за стол не садился.
 * Открытая дверь по коду, без пропуска, поэтому в ответе одни числа: есть ли
 * комната, этап, сколько живых людей, сколько мест и сколько секунд стол
 * ещё подождёт без единого касания. Комнаты нет — говорим, закрылась ли она
 * только что (коды убранных комнат помнятся недолго) или её не было вовсе.
 */
function состояниеСтола(кодОтИгрока) {
  const код = привестиКод(кодОтИгрока);
  if (!код) return { есть: false, закрылся: false };
  const комната = комнаты.get(код);
  if (!комната) return { есть: false, закрылся: убранные.has(код) };
  const осталось = срокЖизни(комната) - (Date.now() - комната.трогали);
  return {
    есть: true,
    игра: комната.игра || реестр.ПО_УМОЛЧАНИЮ,   // во что тут играют
    этап: комната.этап,
    людей: людиЗаСтолом(комната).length,
    мест: комната.мест,
    ждётЕщёСекунд: Math.max(0, Math.ceil(осталось / 1000))
  };
}

/**
 * Сколько комната живёт без единого касания. Короткий срок — только для
 * комнаты, в которой ещё ни разу не играли: там пока ничего не потеряно,
 * а место на сервере она занимает. Считаем по числу сыгранных партий,
 * а не по одному этапу: компания, вернувшаяся в прихожую пересобрать стол,
 * стоит на том же этапе «ожидание», но это живая игра, а не пустышка.
 */
function срокЖизни(комната) {
  const ещёНеИграли = комната.этап === 'ожидание' && комната.сыграно === 0;
  return ещёНеИграли ? ЖИЗНЬ_ПУСТОЙ_КОМНАТЫ : ЖИЗНЬ_БРОШЕННОЙ_КОМНАТЫ;
}

/**
 * Хозяин не вышел, а просто пропал со связи — закрыл вкладку, спустился
 * в метро, кончился интернет. Звание отдаём тому, кто за столом сейчас
 * есть и может нажимать кнопки.
 *
 * Здесь два отличия от передачи при выходе, и оба нарочные:
 *
 *   — если на связи нет никого, звание НЕ трогаем. Перекладывать его
 *     с одного молчащего на другого бессмысленно: нажать всё равно
 *     некому, а хозяин у стола за это время сменился бы дважды;
 *   — обратно, когда связь вернётся, звание не переходит. Иначе оно
 *     прыгало бы туда-сюда при каждом обрыве, и никто бы не понимал,
 *     у кого сейчас кнопки. Вернувшийся остаётся за столом обычным
 *     игроком — это честнее мигающих кнопок.
 */
function хозяинПропалСоСвязи(комната) {
  const наСвязи = людиНаСвязи(комната);
  if (наСвязи.length === 0) return;
  комната.хозяин = наСвязи[0];
}

/** Убрать комнату и отпустить всех, кто ещё висит на опросе. */
function удалитьКомнату(код) {
  const комната = комнаты.get(код);
  if (!комната) return;
  учестьИтогПартии(комната);  // шла партия — значит, её бросили
  отменитьХодБота(комната);   // ботам в убранной комнате ходить некуда
  const ждали = комната.ждущие;
  комната.ждущие = [];
  for (const ждущий of ждали) {
    clearTimeout(ждущий.таймер);
    ждущий.позвать(null);
  }
  комнаты.delete(код);
  запомнитьУбранныйКод(код);
}

/**
 * Запомнить код убранной комнаты — ненадолго и без всяких подробностей.
 * Нужно только затем, чтобы опоздавшему другу ответить «партия закрылась»
 * вместо «такого кода нет» и не записать ему штрафную неудачу.
 */
function запомнитьУбранныйКод(код) {
  // Держим память ограниченной: самый старый код выкидываем.
  if (убранные.size >= ПОМНИМ_УБРАННЫХ_КОДОВ) {
    const самыйСтарый = убранные.keys().next();
    if (!самыйСтарый.done) убранные.delete(самыйСтарый.value);
  }
  убранные.delete(код);          // чтобы код встал в конец очереди по времени
  убранные.set(код, Date.now());
}

/** Выкинуть из памяти коды, убранные слишком давно. */
function забытьСтарыеКоды(время) {
  for (const [код, когда] of убранные) {
    // Map хранит записи по порядку добавления: как только дошли до свежей,
    // дальше все свежие — обходить остаток незачем.
    if (время - когда <= ПОМНИМ_УБРАННЫЙ_КОД) break;
    убранные.delete(код);
  }
}

/**
 * Обход всех комнат: отмечаем пропавших игроков и выбрасываем брошенные
 * комнаты. Вызывается по таймеру, но вынесен отдельно, чтобы проверка
 * могла позвать его руками и не ждать полминуты.
 */
function прибратьсяСейчас(сейчас) {
  const время = сейчас || Date.now();
  забытьСтарыеКоды(время);

  for (const [код, комната] of комнаты) {
    /* Срок — см. срокЖизни: пустышке пять минут, живой игре пятнадцать.
       Почему по числу партий, а не по этапу, — там же: пересборка стола
       (см. пересобратьСтол) укорачивала бы комнате жизнь втрое. */
    if (время - комната.трогали > срокЖизни(комната)) {
      удалитьКомнату(код);
      continue;
    }

    /* Кто давно молчит и не ждёт новостей — тот потерял связь.
       Остальные узнают об этом сами, без действий со своей стороны.
       Ботов это не касается вовсе: у них нет ни связи, ни запросов. */
    let что_то_изменилось = false;
    const пропалиНасовсем = [];
    for (const ктоЯ of занятыеМеста(комната)) {
      const игрок = комната.игроки[ктоЯ];
      if (игрок.этоБот || игрок.ушёл) continue;
      if (ждётСейчас(комната, ктоЯ)) continue;   // держит открытый опрос — жив

      const молчит = время - игрок.последнийЗапрос;

      // Молчит так долго, что ждать его дальше бессмысленно.
      if (молчит > ПРОПАЛ_НАСОВСЕМ) {
        пропалиНасовсем.push(ктоЯ);
        continue;
      }

      if (игрок.наСвязи && молчит > МОЛЧАНИЕ_ЭТО_ОБРЫВ) {
        игрок.наСвязи = false;
        что_то_изменилось = true;
        /* Пропал со связи хозяин — звание уходит тому, кто за столом сейчас
           есть. Иначе прихожая застывает: человек закрыл вкладку или спустился
           в метро, а остальные все три минуты (пока его не выведет строка
           выше) не могут ни посадить бота, ни начать игру.
           Назад звание не возвращается — см. хозяинПропалСоСвязи. */
        if (ктоЯ === комната.хозяин) хозяинПропалСоСвязи(комната);
      }
    }

    /* Пропавшего насовсем выводим тем же путём, что и того, кто нажал
       «выйти»: за столом на двоих партия закрывается без победителя,
       а в компании его место занимает бот, и остальные играют дальше.
       Разбудить остальных «выйти» умеет само, отдельно звать не надо. */
    if (пропалиНасовсем.length) {
      /* Второй довод — «его вывело молчание, сам он не прощался». По нему
         человеку потом открывают дорогу назад: партия для остальных
         не встала, а вернувшемуся не придётся начинать всё сначала. */
      for (const ктоЯ of пропалиНасовсем) выйти(комната, ктоЯ, true);
      continue;
    }

    if (что_то_изменилось) разбудить(комната);

    /* Сторож насоса ботов.

       Проверка дешёвая, а держит она то, что дисциплиной не удержать:
       ход за ботом, партия идёт, а таймера нет — значит насос где-то
       умер, и без вмешательства комната простоит так навсегда. Человек
       при этом видит «ходит Бот 3» и ничего не может сделать: он висит
       на длинном опросе, а опрос насос не заводит.

       Почему это не лишняя перестраховка. Все прочие меры держатся на
       том, что каждая новая дорога, меняющая партию, не забудет позвать
       ботыДумают. По истории этого файла на такой дисциплине уже
       спотыкались, и сторож — единственное место, которое превращает
       «зависло навсегда» в «заминка на пару секунд». */
    поднятьУснувшийНасос(комната);
  }
}

/**
 * Разбудить насос ботов, если он молчит, а ходить очередь бота.
 * Ничего не делает в обычной жизни: там таймер уже заведён.
 *
 * Живой будильник эта функция НЕ трогает — в этом её отличие от ботыДумают,
 * и на этом отличии держится отклонённый ход (см. сделатьХод): туда можно
 * стучать сколько угодно раз в секунду, будильник от этого не сдвинется.
 */
function поднятьУснувшийНасос(комната) {
  if (комната.этап !== 'игра' || комната.таймерБота) return;
  /* Есть ли повод — ход за ботом или бросок заходной, — решает сам насос:
     повторять здесь его условия значило бы однажды разойтись с ним.
     Живой таймер выше уже отсеян, значит гасить тут нечего. */
  ботыДумают(комната);
}

let уборщик = null;

/** Запустить уборку по таймеру. Таймер не держит программу запущенной. */
