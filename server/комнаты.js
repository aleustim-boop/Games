'use strict';

/* =====================================================================
   Комнаты: где живут партии — от двух до шести игроков.

   Всё хранится в памяти. Перезапустили сервер — комнаты пропали,
   для первой версии так и задумано: ни базы, ни файлов, ни платы
   за хостинг.

   Про сеть этот файл не знает ничего: он не умеет ни читать запросы,
   ни писать ответы. Тот, кто ждёт новостей, оставляет здесь свою
   функцию «позвать меня, когда что-то случится». Так части не путаются:
   ошибка в правилах ищется в партия-по-сети.js, ошибка в передаче —
   в сервер.js, а здесь — только жизнь самих комнат.

   Личных данных не храним: ни телеграм-номеров, ни чего-либо ещё. Только
   код комнаты, секретные пропуска, состояние партии и короткое имя вроде
   «Игрок 3», чтобы за столом было понятно, кто есть кто.

   Как живёт комната на компанию:

     1. Человек создаёт комнату и получает код из четырёх знаков.
     2. Друзья входят по коду — комната ждёт, все видят, кто уже сел.
        Больше шести человек за стол не садится.
     3. Создатель выбирает разновидность игры (обычная или переводная,
        парами или нет) и, если друзей мало, сажает на пустые места ботов.
     4. Создатель нажимает «Начать» — карты раздаются. Раньше двух игроков
        начать нельзя.
     5. Идёт партия: ходы людей приходят запросами, за ботов ходит сам
        сервер. После конца — «Сыграть ещё», и всё повторяется.
     6. Захотели поменять состав или правила — хозяин жмёт «Пересобрать
        стол», и комната возвращается в пункт 2: та же прихожая и тот же
        код. Так можно убрать бота, впустить опоздавшего друга и выбрать
        другую игру, не создавая новой комнаты.

   Комната на двоих осталась прежней: там друг входит по коду, и партия
   начинается сама, без всякой кнопки. Это нарочно — старая игра вдвоём
   работает ровно как работала.
   ===================================================================== */

