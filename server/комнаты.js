'use strict';

/* =====================================================================
   Комнаты: где живут партии — от двух до шести игроков.

   Всё хранится в памяти. Перезапустили сервер — комнаты пропали,
   для первой версии так и задумано: ни базы, ни файлов, ни платы
   за хостинг.

   Про сеть этот файл не знает ничего: он не умеет ни читать запросы,
   ни писать ответы. Тот, кто ждёт новостей, оставляет здесь свою
   функцию «позвать меня, когда что-то случится». Так части не путаются:
   ошибка в правилах ищется в партия-по-сети.js, ошибка в передаче —
   в сервер.js, а здесь — только жизнь самих комнат.

   Личных данных не храним: ни телеграм-номеров, ни чего-либо ещё. Только
   код комнаты, секретные пропуска, состояние партии и короткое имя вроде
   «Игрок 3», чтобы за столом было понятно, кто есть кто.

   Как живёт комната на компанию:

     1. Человек создаёт комнату и получает код из четырёх знаков.
     2. Друзья входят по коду — комната ждёт, все видят, кто уже сел.
        Больше шести человек за стол не садится.
     3. Создатель выбирает разновидность игры (обычная или переводная,
        парами или нет) и, если друзей мало, сажает на пустые места ботов.
     4. Создатель нажимает «Начать» — карты раздаются. Раньше двух игроков
        начать нельзя.
     5. Идёт партия: ходы людей приходят запросами, за ботов ходит сам
        сервер. После конца — «Сыграть ещё», и всё повторяется.

   Комната на двоих осталась прежней: там друг входит по коду, и партия
   начинается сама, без всякой кнопки. Это нарочно — старая игра вдвоём
   работает ровно как работала.
   ===================================================================== */

const крипто = require('crypto');
const партии = require('./партия-по-сети.js');
/* Правила игры нужны здесь ровно за одним — списком уровней, которыми умеет
   играть бот (см. УРОВНИ_БОТОВ ниже). Подключаем их так же, как это делает
   партия-по-сети.js: правила у сервера и у браузера одни и те же. */
const правила = require('../js/game.js');

/* Буквы и цифры, которые не путаются на слух и на вид: нет нуля и буквы O,
   нет единицы, I и L. Код можно продиктовать голосом по телефону. */
const АЛФАВИТ_КОДА = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';
const ДЛИНА_КОДА = 4;

/* Сколько ждать, прежде чем считать, что игрок потерял связь.

   Тонкость: пока игрок висит на длинном опросе, новых запросов от него
   не приходит — молчание тут ничего не значит. Поэтому «на связи» —
   это либо недавний запрос, либо открытое ожидание новостей прямо
   сейчас. При таком счёте порог можно ставить коротким: оборванное
   соединение сервер видит сразу, а этот срок нужен лишь на случай,
   когда связь пропала тихо (например, у человека кончился интернет). */
const МОЛЧАНИЕ_ЭТО_ОБРЫВ = 12 * 1000;

/* Столько молчания — и мы считаем, что игрок не вернётся, а партию
   заканчиваем так же, как при добровольном выходе.

   Зачем нужен отдельный срок. Пометка «не на связи» (12 секунд выше) партию
   не заканчивает: человек мог войти в метро или переключиться на звонок,
   через минуту вернётся и доиграет. Но если он закрыл телефон насовсем,
   оставшемуся ждать нечего — а сам он этого не узнает никогда: комната живёт,
   пока в неё ходит хоть кто-то, и его же собственные опросы держат её вечно.
   Раньше в такой партии ход навсегда оставался за пропавшим.

   Почему три минуты: меньше — и обидно оборвётся партия из-за поездки в лифте
   или пересадки на другую сеть; больше — человек столько не ждёт, он закроет
   игру раньше, чем сервер признает друга пропавшим. */
const ПРОПАЛ_НАСОВСЕМ = 3 * 60 * 1000;

/* Комната без единого запроса столько времени считается брошенной.
   Это последняя страховка от утечки памяти, а не рабочий срок: людей,
   закрывших телефон, гораздо раньше разбирает ПРОПАЛ_НАСОВСЕМ (три минуты
   молчания — и партия закрывается сама). Досюда доживает только то, чего
   он не касается: например, комната, из которой оба вышли не попрощавшись
   в самый первый миг. Пятнадцать минут тут взяты с запасом. */
const ЖИЗНЬ_БРОШЕННОЙ_КОМНАТЫ = 15 * 60 * 1000;

/* А пустая комната, в которую так никто и не вошёл, живёт меньше.

   Пять минут — это про самый обычный случай: человек создал партию,
   нажал «Скопировать код», ушёл в переписку отправлять его другу,
   телефон погас. Пока игра открыта, она сама спрашивает новости и комнату
   трогает, но у спящего телефона отсчёт идёт. Друг с ПРАВИЛЬНЫМ кодом
   не должен слышать «комната не найдена» — это самая обидная жалоба,
   какая бывает, потому что код и правда верный.

   Раньше здесь стояло две минуты — их поставили, чтобы скрипт не забивал
   сервер пустыми комнатами. Теперь эту работу делает потеснитьЖадного:
   когда мест не хватает, место отбирают у того, кто нахватал брошенных
   комнат, а не у того, кто честно ждёт друга. Поэтому короткий срок
   больше не нужен. */
const ЖИЗНЬ_ПУСТОЙ_КОМНАТЫ = 5 * 60 * 1000;

/* Как часто обходим комнаты: проверяем, кто пропал, и убираем брошенные.
   Часто — потому что от этого зависит, как быстро человек узнает,
   что друг исчез. Обход дешёвый: пробежка по нескольким комнатам. */
const УБОРКА_КАЖДЫЕ = 3 * 1000;

/* Больше этого числа комнат разом не держим. Домашнему серверу столько
   и не нужно — потолок нужен на случай, когда комнаты создают без счёта:
   между уборками память иначе росла бы неограниченно. */
const ПОТОЛОК_КОМНАТ = 300;

/* Сколько забытых комнат с одного адреса — это уже перебор.

   Забытая комната — та, в которой не сделали ни одного хода и о которой
   давно никто не спрашивал. Живая игра спрашивает у сервера новости
   постоянно, а скрипт, дёргающий «создать» в цикле, не спрашивает ничего
   и никогда. Столько забытых комнат подряд один адрес держать не должен:
   если из-за них живому игроку не хватило места, мы этот адрес подвинем
   (см. потеснитьЖадного).

   Было двадцать — стало две. Двадцать обходились слишком просто: хватало
   раскидать комнаты по пятнадцать штук на двадцать адресов, и порог
   не срабатывал ни у кого. Пять тоже мало помогло: замер показал, что
   скрипт с сорока адресами держится ровно под порогом (около 4,7 забытых
   комнат на адрес) и живой игрок не входит ни разу за минуту.

   Две — это уже не «случайность», а привычка: живой человек играет
   в одну партию, а не бросает по две подряд. И заметьте, чем мы жертвуем:
   комнатой, в которой не сделали ни одного хода и о которой никто
   не спрашивал полминуты, — да ещё и только тогда, когда все триста мест
   заняты и живому игроку иначе не войти вовсе. */
const ЗАБЫТЫХ_КОМНАТ_С_АДРЕСА = 2;

/* Столько комнат разом с одного адреса — и на полном сервере мы этому
   адресу новых мест не даём совсем (см. потеснитьЖадного, шаг 0).

   Почему не два, как выше. За одним адресом может сидеть несколько живых
   пар: общий wi-fi в кафе, школе или у оператора связи — там у всех
   гостей адрес один. Четыре одновременные партии с одного адреса — это
   ещё похоже на людей, пять и больше — уже нет. И напомним, что правило
   включается, только когда все триста мест заняты: при свободном сервере
   никому ничего не запрещается. */
const ДЕРЖИТ_КОМНАТ_МНОГО = 5;

/* Сколько комната может молчать, прежде чем мы сочтём её забытой.
   Полминуты — потому что длинный опрос длится 25 секунд: живая игра
   даёт о себе знать чаще, у неё комнату не отнимут. */
const ЗАБЫТАЯ_ПУСТАЯ_КОМНАТА = 30 * 1000;

/* А комнате, у которой не спросили новостей НИ РАЗУ, полминуты не нужно.
   Игра запускает опрос в тот же миг, когда получила код (см. js/сеть.js,
   начатьЖизньВКомнате: последняя строка — запуститьОпрос), так что первый
   вопрос приходит через одну пересылку по сети. Пять секунд — запас
   на медленный телефон, и всё.

   Почему это важно. Пока запас был большой, скрипт держал все триста мест
   почти даром: раз в полминуты обновлял свои комнаты новыми, а свежую
   комнату трогать нельзя. С коротким запасом та же затея стоит уже
   двух сотен запросов в секунду. */
const НЕ_СПРОСИЛИ_НИ_РАЗУ = 5 * 1000;

/* Сколько помним коды убранных комнат и сколько их помним штук.

   Нужно ровно для одного: отличить «такого кода никогда не было»
   (похоже на подбор) от «код был, но комнату уже убрали» (человек
   не виноват, штрафовать его нельзя). Кроме кода и времени тут ничего
   не хранится, так что памяти это стоит копейки. */
const ПОМНИМ_УБРАННЫЙ_КОД = 10 * 60 * 1000;
const ПОМНИМ_УБРАННЫХ_КОДОВ = 2000;

/* Каким соперником играет бот, если создатель комнаты не выбрал другого.
   «Обычный» — середина: не ошибается, как новичок, но и не считает карты. */
const СЛОЖНОСТЬ_БОТОВ = 'обычный';

/* Все уровни, которыми бот вообще умеет играть. Список спрашиваем у самих
   правил, а не переписываем сюда вторым: две копии однажды разойдутся, и тогда
   выбранный за столом уровень тихо перестанет доходить до бота. */
const УРОВНИ_БОТОВ = правила.СЛОЖНОСТИ;

/* Сколько знаков оставляем от имени, которым игрок назвался.
   Длинное имя всё равно не поместится в список за столом, а лишние
   буквы — это только лишняя память на каждой комнате. */
const ДЛИНА_ИМЕНИ = 16;

/** Все живые комнаты: код → комната. */
const комнаты = new Map();

/** Коды недавно убранных комнат: код → когда убрали. */
const убранные = new Map();

/* ---------------------------------------------------------------------
   Коды и пропуска
   --------------------------------------------------------------------- */

/** Случайный код из безопасного алфавита. Случайность берём криптостойкую. */
function новыйКод() {
  let код = '';
  const байты = крипто.randomBytes(ДЛИНА_КОДА);
  for (let i = 0; i < ДЛИНА_КОДА; i++) {
    код += АЛФАВИТ_КОДА[байты[i] % АЛФАВИТ_КОДА.length];
  }
  return код;
}

/**
 * Код, которого сейчас нет ни у одной живой комнаты.
 * Не нашли за 200 попыток — возвращаем null.
 *
 * Раньше на этот случай выдавался код двойной длины, но в поле ввода
 * помещается только четыре-шесть знаков: такой код игрок просто не смог бы
 * набрать. Честный отказ понятнее, чем комната, в которую нельзя войти.
 */
function свободныйКод() {
  for (let попытка = 0; попытка < 200; попытка++) {
    const код = новыйКод();
    if (!комнаты.has(код)) return код;
  }
  return null;
}

/**
 * Привести введённый код к общему виду: человек может набрать строчными,
 * с пробелом или дефисом посередине. Лишние символы просто выкидываем.
 */
function привестиКод(что) {
  if (typeof что !== 'string') return '';
  return что.toUpperCase().replace(/[^A-Z0-9]/g, '').slice(0, 12);
}

/** Пропуск — длинный случайный ключ, по нему игрок возвращается после обрыва. */
function новыйПропуск() {
  return крипто.randomBytes(16).toString('hex');
}

/* ---------------------------------------------------------------------
   Создание комнаты и вход
   --------------------------------------------------------------------- */

function новыйИгрок(место, имя) {
  return {
    пропуск: новыйПропуск(),
    имя: имя || партии.имяПоУмолчанию(место),
    этоБот: false,
    уровень: null,       // уровень игры — только у ботов
    последнийЗапрос: Date.now(),
    наСвязи: true,
    ушёл: false,         // нажал «выйти» сам, а не просто пропал
    хочетЕщё: false      // предложил сыграть ещё партию
  };
}

/**
 * Бот за столом. Пропуска у него нет вовсе — значит, войти под его именем
 * нельзя ни случайно, ни нарочно: найтиИгрока пускает только по строке-пропуску.
 */
function новыйБот(место, уровень) {
  return {
    пропуск: null,
    имя: партии.имяБота(место),
    этоБот: true,
    уровень: уровень || СЛОЖНОСТЬ_БОТОВ,
    последнийЗапрос: Date.now(),
    наСвязи: true,
    ушёл: false,
    хочетЕщё: true       // бот всегда согласен сыграть ещё
  };
}

/* ---------------------------------------------------------------------
   Места за столом
   --------------------------------------------------------------------- */

/** Все места этой комнаты по порядку — и занятые, и пустые. */
function местаКомнаты(комната) {
  return партии.МЕСТА.slice(0, комната.мест);
}

/** Кто уже сидит за столом, в порядке мест. */
function занятыеМеста(комната) {
  return местаКомнаты(комната).filter(function (место) {
    return Boolean(комната.игроки[место]);
  });
}

/**
 * Номер последнего занятого места (1 — первое место, 0 — за столом пусто).
 *
 * Нужно там, где стол уменьшают: считать по числу сидящих нельзя, потому что
 * места в середине бывают пустыми — например, второй игрок вышел из прихожей,
 * а третий остался. По числу сидящих третий оказался бы за границей стола
 * и пропал бы у всех с экрана, хотя никуда не уходил.
 */
function докудаЗанятСтол(комната) {
  const занятые = занятыеМеста(комната);
  if (занятые.length === 0) return 0;
  return партии.номерМеста(занятые[занятые.length - 1]);
}

/** Первое свободное место или null, если стол полон. */
function свободноеМесто(комната) {
  for (const место of местаКомнаты(комната)) {
    if (!комната.игроки[место]) return место;
  }
  return null;
}

/** Живые люди за столом: не боты и не ушедшие. */
function людиЗаСтолом(комната) {
  return занятыеМеста(комната).filter(function (место) {
    const игрок = комната.игроки[место];
    return !игрок.этоБот && !игрок.ушёл;
  });
}

/**
 * Список сидящих для показа игроку. Внутренние имена мест в нём есть
 * (поле «ключ»), но наружу он не уходит: видДляИгрока превращает его
 * в «застолом» и сам список выбрасывает.
 */
function списокМест(комната) {
  return занятыеМеста(комната).map(function (место) {
    const игрок = комната.игроки[место];
    return {
      ключ: место,
      имя: игрок.имя,
      этоБот: игрок.этоБот,
      хозяин: место === комната.хозяин,
      наСвязи: игрок.этоБот ? true : (игрок.наСвязи && !игрок.ушёл),
      ушёл: игрок.ушёл,
      хочетЕщё: игрок.хочетЕщё
    };
  });
}

/** Место игрока по его пропуску или null. */
function местоПоПропуску(комната, пропуск) {
  if (typeof пропуск !== 'string' || !пропуск) return null;
  for (const место of местаКомнаты(комната)) {
    const игрок = комната.игроки[место];
    if (игрок && игрок.пропуск === пропуск) return место;
  }
  return null;
}

/**
 * Забытая комната — та, которую держат зря.
 *
 * Раньше признаком было совпадение двух времён (трогали === создана),
 * то есть по сути случайность: два независимых замера Date.now() обязаны
 * были попасть в одну миллисекунду. Под нагрузкой миллисекунда
 * перескакивает, и часть мусорных комнат навсегда переставала считаться
 * забытыми — защита тихо слабела как раз тогда, когда она нужна.
 * Поэтому теперь спрашиваем прямо, а не гадаем по времени:
 *
 *   1) сделали ли в комнате хоть один ход;
 *   2) спрашивал ли кто-нибудь у неё новости (поле «спрашивали»);
 *   3) давно ли к ней вообще обращались.
 *
 * Закрытые комнаты (те, куда друг уже вошёл) считаются наравне с пустыми.
 * Иначе самый дешёвый способ занять сервер выглядел так: два запроса
 * подряд — «создать» и «войти» тем же кодом, — и комнату не тронет никто
 * до самого конца её жизни.
 */
function комнатаЗабыта(комната, время) {
  // Хоть один ход — это живая партия, её не трогаем никогда.
  if (комната.номерСобытия > 0) return false;
  // Ни разу не спросили новостей — это не игра, а скрипт.
  if (!комната.спрашивали) return время - комната.создана > НЕ_СПРОСИЛИ_НИ_РАЗУ;
  // Спросили и пропали: живая игра держит опрос постоянно.
  return время - комната.трогали > ЗАБЫТАЯ_ПУСТАЯ_КОМНАТА;
}

/** Сколько комнат сейчас числится за этим адресом. */
function сколькоКомнатУАдреса(чей) {
  let сколько = 0;
  for (const комната of комнаты.values()) {
    if (комната.создатель === чей) сколько++;
  }
  return сколько;
}

/** Самая давняя забытая комната этого адреса — или null, если таких нет. */
function самаяДавняяЗабытая(чей, время) {
  let давняя = null;
  for (const комната of комнаты.values()) {
    if (комната.создатель !== чей || !комнатаЗабыта(комната, время)) continue;
    if (!давняя || комната.создана < давняя.создана) давняя = комната;
  }
  return давняя;
}

/**
 * Потеснить того, кто нахватал забытых комнат.
 *
 * Зачем. Потолок в 300 комнат забивается простым скриптом за секунду,
 * и дальше живые люди получают «Сервер сейчас занят», пока эти комнаты
 * не состарятся. Отказывать честному игроку из-за чужого мусора нечестно,
 * поэтому, когда места нет, мы освобождаем одно.
 *
 * Порядок такой:
 *
 *   0. Тому, кто сам держит слишком много комнат, места не даём вовсе —
 *      ни за чужой счёт, ни за счёт своих же брошенных. Без этого правила
 *      скрипт крутил свои триста мест по кругу: комната состарилась —
 *      он тут же меняет её на свежую, и для остальных забытых комнат
 *      на сервере не остаётся никогда. Замер это и показал: живой игрок
 *      не мог создать партию ни разу за двадцать секунд.
 *
 *   1. Дальше смотрим на свои же забытые комнаты. Есть такая — убираем
 *      её, а чужого не трогаем вовсе: человек просто меняет свою брошенную
 *      партию на новую, и общее число комнат от этого не растёт.
 *
 *   2. Только если своих забытых нет, ищем адрес, который держит больше
 *      всех чужих забытых комнат, и выселяем самую давнюю из них.
 *
 * Комнату с ходами не выселяем ни при каких условиях — там живые люди.
 *
 * Чего это НЕ делает. Скрипт, который раскидает комнаты по сотням адресов
 * (по одной-две на адрес) и будет обновлять их быстрее, чем они стареют,
 * всё равно займёт сервер: по каждому отдельному адресу он выглядит как
 * обычный человек. Дешёвые способы это отсекает, дорогой — нет.
 *
 * Возвращает true, если место освободилось.
 */
function потеснитьЖадного(адрес) {
  const время = Date.now();

  if (адрес && сколькоКомнатУАдреса(адрес) >= ДЕРЖИТ_КОМНАТ_МНОГО) return false;

  const своя = адрес ? самаяДавняяЗабытая(адрес, время) : null;
  if (своя) {
    удалитьКомнату(своя.код);
    return true;
  }

  const счёт = new Map();
  for (const комната of комнаты.values()) {
    if (!комната.создатель || комната.создатель === адрес) continue;
    if (!комнатаЗабыта(комната, время)) continue;
    счёт.set(комната.создатель, (счёт.get(комната.создатель) || 0) + 1);
  }

  let жадный = null;
  let больше_всех = 0;
  for (const [кто, сколько] of счёт) {
    if (сколько > больше_всех) { жадный = кто; больше_всех = сколько; }
  }
  if (!жадный || больше_всех < ЗАБЫТЫХ_КОМНАТ_С_АДРЕСА) return false;

  const самаяДавняя = самаяДавняяЗабытая(жадный, время);
  if (!самаяДавняя) return false;

  удалитьКомнату(самаяДавняя.код);
  return true;
}

/**
 * Привести к порядку имя, которым назвался игрок.
 *
 * Оставляем только буквы, цифры, пробелы и дефисы: кавычки, скобки
 * и прочие знаки в имени не нужны никому, а бед натворить могут.
 * Пустое или непонятное имя — не беда, тогда игрок будет «Игрок 3».
 */
function привестиИмя(что, место) {
  if (typeof что !== 'string') return партии.имяПоУмолчанию(место);
  const чистое = что.replace(/[^0-9A-Za-zА-Яа-яЁё \-]/g, '').replace(/\s+/g, ' ').trim();
  if (!чистое) return партии.имяПоУмолчанию(место);
  /* Внутренними именами мест ('человек', 'бот-3') назваться нельзя:
     эти слова наружу не ходят никогда, и путать их с именем игрока
     не должен ни клиент, ни проверка, которая ищет утечки по словам. */
  if (партии.МЕСТА.indexOf(чистое) !== -1) return партии.имяПоУмолчанию(место);
  return чистое.slice(0, ДЛИНА_ИМЕНИ);
}

/**
 * Уровень бота из настроек: настоящий — как есть, всё остальное — null,
 * то есть «уровень не назвали».
 *
 * Зачем проверка. Раньше это поле принималось любой строкой любой длины,
 * ложилось в комнату и уходило обратно ВСЕМ, кто сидит за столом (см.
 * показатьИгроку). Двух тысяч знаков хватало, чтобы засорить чужие экраны
 * и раздуть каждый ответ сервера.
 *
 * Почему мусор — не отказ. Эти слова человек не набирает руками, их шлёт
 * страница игры. Значит, непонятное значение — не вина того, кто нажал
 * кнопку, и партию из-за него останавливать незачем: просто оставляем
 * уровень, который был.
 */
function уровеньИзСписка(значение) {
  if (typeof значение !== 'string') return null;
  return УРОВНИ_БОТОВ.indexOf(значение) !== -1 ? значение : null;
}

/** Число из настроек в разумных пределах; мусор — это «не сказано». */
function числоВПределах(значение, снизу, сверху) {
  const число = Number(значение);
  if (!Number.isFinite(число)) return null;
  return Math.min(сверху, Math.max(снизу, Math.floor(число)));
}

/**
 * Применить к комнате настройки стола: сколько мест, какая разновидность
 * игры, каким соперником играют боты. Возвращает true, если хоть что-то
 * из сказанного оказалось понятным.
 *
 * Мест не может стать меньше, чем уже сидит людей: иначе кто-то оказался бы
 * выставленным из-за стола чужим нажатием.
 */
function применитьНастройки(комната, настройки) {
  if (!настройки || typeof настройки !== 'object') return false;
  let поняли = false;

  if (настройки.парами !== undefined) {
    комната.парами = настройки.парами === true;
    поняли = true;
    /* Парная игра бывает только вчетвером, поэтому стол сразу расширяем
       до четырёх мест: иначе создатель выбрал бы режим, а начать не смог.
       И это уже названное число мест — дальше стол сам не растёт. */
    if (комната.парами) {
      комната.мест = Math.max(комната.мест, партии.ИГРОКОВ_В_ПАРАХ);
      комната.местВыбрали = true;
    }
  }
  if (настройки.переводной !== undefined) {
    комната.переводной = настройки.переводной === true;
    поняли = true;
  }

  const мест = числоВПределах(настройки.мест, партии.МИН_ИГРОКОВ, партии.МАКС_ИГРОКОВ);
  if (мест !== null) {
    /* Меньше, чем занято, стол сделать нельзя — иначе сидящий на дальнем месте
       просто исчез бы со стола от чужого нажатия. Считаем именно по номеру
       последнего занятого места, а не по числу сидящих: места в середине
       бывают пустыми (человек вышел из прихожей). */
    комната.мест = Math.max(мест, докудаЗанятСтол(комната));
    комната.местВыбрали = true;
    поняли = true;
  }

  /* Проверка стоит именно здесь, а не у тех, кто сюда обращается: через эту
     дверь настройки приходят и при создании комнаты, и старым действием
     «настройки» — так закрыты оба входа разом. */
  const уровень = уровеньИзСписка(настройки.уровеньБотов);
  if (уровень !== null) {
    комната.уровеньБотов = уровень;
    поняли = true;
  }
  return поняли;
}

/**
 * Создать пустую комнату. Вернёт код и пропуск создателя,
 * а если комнат уже слишком много — понятный отказ вместо поломки.
 *
 * Адрес создателя нужен только для одного: когда места нет, разобрать,
 * из-за кого именно его нет. Программа, дёргающая «создать» в цикле,
 * не должна закрывать вход живым игрокам.
 *
 * Второй довод — настройки стола: { мест, переводной, парами, уровеньБотов,
 * имя }. Если их не передали вовсе, получается прежняя комната на двоих,
 * которая начинает партию сама, как только вошёл друг. Так сделано нарочно:
 * пока страница игры не научилась показывать прихожую, старая игра вдвоём
 * должна работать точно так же, как работала.
 */
function создатьКомнату(адрес, настройки) {
  // Уперлись в потолок — сначала выкидываем брошенные: скорее всего,
  // место занято теми, кто давно ушёл.
  if (комнаты.size >= ПОТОЛОК_КОМНАТ) прибратьсяСейчас();
  // Всё равно тесно — двигаем того, кто нахватал забытых пустых комнат.
  if (комнаты.size >= ПОТОЛОК_КОМНАТ) потеснитьЖадного(адрес);
  if (комнаты.size >= ПОТОЛОК_КОМНАТ) {
    return {
      ок: false,
      причина: 'Сервер сейчас занят: слишком много начатых партий. ' +
        'Попробуйте через несколько минут'
    };
  }

  const код = свободныйКод();
  if (!код) {
    return {
      ок: false,
      причина: 'Не получилось подобрать свободный код комнаты. ' +
        'Попробуйте создать партию ещё раз'
    };
  }

  const рождение = Date.now();

  const комната = {
    код: код,
    создатель: адрес || null,   // только чтобы разбирать, кто занял места
    создана: рождение,
    трогали: рождение,        // время последнего запроса от любого игрока
    спрашивали: false,        // спрашивал ли кто-нибудь у этой комнаты новости
    версия: 1,                // растёт при каждом изменении — по ней работают опросы
    этап: 'ожидание',         // 'ожидание' | 'игра' | 'конец'
    компания: false,          // комната на компанию: с прихожей и кнопкой «Начать»
    мест: партии.МИН_ИГРОКОВ, // сколько мест за столом, от двух до шести
    местВыбрали: false,       // человек сам назвал число мест — тогда оно закон
    переводной: false,        // разновидность игры: перевод хода
    парами: false,            // разновидность игры: двое на двоих
    уровеньБотов: СЛОЖНОСТЬ_БОТОВ,
    хозяин: партии.ПЕРВЫЙ,    // кто создал комнату: только он начинает партию
    партия: null,
    событие: null,            // { кто, что } — последнее, что произошло
    номерСобытия: 0,
    сыграно: 0,               // сколько партий уже доиграли в этой комнате
    дуракПрошлойПартии: null, // он ходит первым в следующей партии
    игроки: {},
    ждущие: [],               // те, кто сейчас держит длинный опрос
    таймерБота: null          // отложенный ход бота, чтобы карты не падали разом
  };
  комната.игроки[партии.ПЕРВЫЙ] = новыйИгрок(
    партии.ПЕРВЫЙ, настройки ? привестиИмя(настройки.имя, партии.ПЕРВЫЙ) : null);

  /* Создатель что-то настроил — значит, собирает компанию: комната ждёт
     кнопку «Начать» и рассказывает всем, кто уже за столом. */
  if (применитьНастройки(комната, настройки)) комната.компания = true;

  комнаты.set(код, комната);

  /* Сразу отдаём и первый вид комнаты. Раньше сервер за ним обращался
     обратно — через найтиИгрока, — и та по дороге отмечала, что комнату
     уже спрашивали. Получалось, что каждая комната с рождения выглядела
     «живой», и мусорные комнаты не находились вовсе. */
  return {
    ок: true,
    код: код,
    пропуск: комната.игроки[партии.ПЕРВЫЙ].пропуск,
    состояние: показатьИгроку(комната, партии.ПЕРВЫЙ)
  };
}

/**
 * Войти в комнату по коду. Возвращает пропуск вошедшего.
 *
 * Дверь закрывается, как только мест не осталось или партия началась:
 * код из четырёх символов можно подобрать перебором, и посторонний,
 * угадавший код, не должен попасть в чужую партию. Вернуться после обрыва
 * можно не по коду, а по своему пропуску — он есть только у самого игрока.
 *
 * Второй довод — { имя }: как звать вошедшего за столом. Не назвался —
 * будет «Игрок 3» по номеру места.
 *
 * Адрес гостя тут не нужен: раньше по нему ставили пометку «вошёл
 * в комнату, которую сам же и создал», и сервер по ней решал, прощать ли
 * адресу прошлые промахи. Прощения при входе больше нет вовсе — оно
 * оказалось дырой (см. шлагбаум.js), — а с ним ушла и пометка.
 */
function войтиВКомнату(кодОтИгрока, настройки) {
  const код = привестиКод(кодОтИгрока);
  if (!код) return { ок: false, причина: 'Не указан код комнаты' };

  const комната = комнаты.get(код);
  /* Пометка «кодНеПодошёл» — единственный отказ, который похож на подбор:
     человек назвал код, которого не было ни у одной комнаты. Пустое поле
     и «там уже играют двое» на подбор не похожи совсем — это обычные
     действия живых людей, и считать их попытками взлома нельзя.

     Отдельно стоит код, который просто устарел: комната была, но её уже
     убрали. Человек тут ни в чём не виноват — он набрал ровно то, что ему
     продиктовал друг, — и штрафовать его за это нельзя. Поэтому коды
     убранных комнат мы недолго помним и отвечаем на них по-человечески. */
  if (!комната) {
    if (убранные.has(код)) {
      return {
        ок: false, кодУстарел: true,
        причина: 'Эта партия уже закрылась — слишком долго никто не входил. ' +
          'Попросите друга создать новую и продиктовать код заново'
      };
    }
    return { ок: false, кодНеПодошёл: true, причина: 'Комната с таким кодом не найдена' };
  }
  if (комната.этап !== 'ожидание') {
    return {
      ок: false,
      причина: комната.компания
        ? 'В этой комнате партия уже началась — попросите создать новую'
        : 'В этой комнате уже играют двое'
    };
  }

  const место = свободноеМесто(комната);
  if (!место) {
    return {
      ок: false,
      причина: комната.мест <= 2
        ? 'В этой комнате уже играют двое'
        : 'За этим столом уже собрались все: свободных мест нет'
    };
  }

  комната.игроки[место] = новыйИгрок(
    место, настройки ? привестиИмя(настройки.имя, место) : null);
  комната.трогали = Date.now();

  if (комната.компания) {
    // В прихожей каждый приход — новость: остальные видят, кто сел за стол.
    записатьСобытие(комната, место, 'вошёл');
  } else if (свободноеМесто(комната) === null) {
    /* Прежний порядок для комнаты на двоих: друг вошёл — карты розданы,
       никакой кнопки нажимать не надо. */
    раздатьПартию(комната, null);
  }

  разбудить(комната);   // те, кто уже за столом, ждут этой новости
  ботыДумают(комната);

  /* Вид комнаты отдаём сразу — по той же причине, что и при создании:
     если сервер пойдёт за ним через найтиИгрока, комната тут же будет
     помечена как «у неё спрашивали новости». А два запроса подряд,
     «создать» и «войти», — это самый дешёвый способ занять место
     на сервере, и отличать его от живой пары надо именно по опросам. */
  return {
    ок: true,
    код: код,
    пропуск: комната.игроки[место].пропуск,
    состояние: показатьИгроку(комната, место)
  };
}

/**
 * Отменить только что состоявшийся вход и снова открыть дверь.
 *
 * Зачем это нужно. Браузер игры ждёт ответа десять секунд и, не дождавшись,
 * бросает запрос. Сервер про это не знает и вход всё равно засчитывает —
 * комната закрывается на человека, которого в ней нет. Друг-создатель
 * ждёт соперника вечно, а вошедший при второй попытке слышит
 * «В этой комнате уже играют двое»: комната потеряна, начать заново нельзя.
 * Поэтому оборвавшийся вход мы откатываем: пропуск второго игрока никому
 * не достался, а значит, и игрока никакого нет.
 *
 * Откатываем только совсем свежий вход — пока в комнате ничего не успело
 * произойти. Если партия уже пошла, значит, вошедший на месте и трогать
 * его нельзя. В комнате на компанию проще: пока карты не розданы, место
 * освобождается всегда — оно просто снова становится пустым.
 */
function отменитьВход(кодОтИгрока, пропуск) {
  const комната = комнаты.get(привестиКод(кодОтИгрока));
  if (!комната) return false;

  const место = местоПоПропуску(комната, пропуск);
  if (!место || место === комната.хозяин) return false;   // хозяина не выселяем

  if (комната.компания) {
    if (комната.этап !== 'ожидание') return false;
    delete комната.игроки[место];
    // Рассказ о приходе призрака убираем: этого человека в комнате нет.
    if (комната.событие && комната.событие.кто === место) комната.событие = null;
    комната.трогали = Date.now();
    разбудить(комната);
    return true;
  }

  if (комната.сыграно !== 0 || комната.номерСобытия !== 0) return false;

  delete комната.игроки[место];
  комната.партия = null;
  комната.этап = 'ожидание';
  комната.событие = null;
  комната.трогали = Date.now();
  разбудить(комната);   // создатель снова видит «ждём друга»
  return true;
}

/**
 * Найти игрока по коду и пропуску. Это единственный способ обратиться
 * к своей комнате после входа — код тут уже ничего не открывает,
 * решает пропуск.
 *
 * Здесь же отмечаем, что игрок жив: раз он пришёл со своим пропуском,
 * значит связь есть. Отметка стоит именно тут, а не в каждом обработчике
 * запроса, — иначе её однажды забудут добавить в новый запрос, и игрок
 * будет числиться отключённым, хотя он на месте.
 */
function найтиИгрока(кодОтИгрока, пропуск) {
  const комната = комнаты.get(привестиКод(кодОтИгрока));
  if (!комната) return null;

  const место = местоПоПропуску(комната, пропуск);
  if (!место) return null;
  отметитьЖизнь(комната, место);
  return { комната: комната, ктоЯ: место };
}

/**
 * Просто запомнить время: игрок был на линии вот в эту секунду.
 *
 * Нужно отдельно от «отметитьЖизнь», потому что этим временем мы пользуемся
 * и в конце длинного опроса — а там будить соперника нечем и незачем.
 */
function отметитьВремяЗапроса(комната, ктоЯ) {
  const игрок = комната.игроки[ктоЯ];
  if (!игрок) return;
  игрок.последнийЗапрос = Date.now();
  комната.трогали = игрок.последнийЗапрос;
  /* Честная отметка «у этой комнаты хоть раз спрашивали». По ней видно
     живую игру: скрипт, который дёргает «создать» в цикле, не спрашивает
     ничего и никогда. Раньше вместо отметки сравнивали два времени
     и надеялись, что они совпадут до миллисекунды. */
  комната.спрашивали = true;
}

/** Отметить, что игрок только что дал о себе знать. */
function отметитьЖизнь(комната, ктоЯ) {
  const игрок = комната.игроки[ктоЯ];
  if (!игрок) return;
  отметитьВремяЗапроса(комната, ктоЯ);
  if (!игрок.наСвязи && !игрок.ушёл) {
    игрок.наСвязи = true;
    разбудить(комната);   // соперник должен увидеть, что игрок вернулся
  }
}

/* ---------------------------------------------------------------------
   Что игрок видит
   --------------------------------------------------------------------- */

/**
 * Полный ответ одному игроку. Карты сюда попадают только через
 * видДляИгрока из партия-по-сети.js — это единственная дверь наружу,
 * своей сборки состояния здесь нет и быть не должно.
 *
 * Поля со словом «соперник» остались с тех времён, когда за столом всегда
 * сидели двое. В комнате на двоих они значат ровно то же, что и раньше;
 * за столом побольше «соперник» — это все остальные разом, а разбираться,
 * кто есть кто, надо по списку «застолом».
 *
 * Комнате на компанию к ответу добавляется прихожая: сколько мест, кто
 * за столом, кто хозяин, можно ли уже начинать и какая выбрана игра.
 * Комнате на двоих ничего этого не добавляется — её ответ должен остаться
 * ровно таким, каким был, иначе старая страница игры увидит незнакомое.
 */
function показатьИгроку(комната, ктоЯ) {
  const я = комната.игроки[ктоЯ];
  const места = списокМест(комната);
  const другие = места.filter(function (место) { return место.ключ !== ктоЯ; });

  const обёртка = {
    код: комната.код,
    этап: комната.этап,
    версия: комната.версия,
    соперникПришёл: другие.length > 0,
    соперникНаСвязи: другие.some(function (м) { return м.наСвязи; }),
    соперникУшёл: другие.length > 0 && другие.every(function (м) { return м.ушёл; }),
    /* Признак «это компания» передаём прямо: только по нему видно, звать
       ли ходившего по имени. По длине списка мест решать нельзя — комната
       на компанию бывает и на два места, а список приходит одинаковый. */
    событие: партии.текстСобытия(комната.событие, ктоЯ, места, комната.компания),
    номерСобытия: комната.номерСобытия,
    сыграноПартий: комната.сыграно,
    яХочуЕщё: Boolean(я && я.хочетЕщё),
    соперникХочетЕщё: другие.length > 0 && другие.every(function (м) { return м.хочетЕщё; })
  };

  if (комната.компания) {
    обёртка.места = места;          // сырой список; наружу его превратят в «застолом»
    обёртка.мест = комната.мест;
    обёртка.мойНомер = партии.номерМеста(ктоЯ);
    обёртка.яХозяин = ктоЯ === комната.хозяин;
    обёртка.можноНачать = комната.этап === 'ожидание' && места.length >= партии.МИН_ИГРОКОВ;
    обёртка.переводной = комната.переводной;
    обёртка.парами = комната.парами;
    обёртка.уровеньБотов = комната.уровеньБотов;
  }
  return партии.видДляИгрока(комната.партия, ктоЯ, обёртка);
}

/* ---------------------------------------------------------------------
   Новости: длинные опросы
   --------------------------------------------------------------------- */

/**
 * Что-то изменилось: поднимаем номер версии и будим всех, кто ждёт.
 * Каждому уходит его собственный вид — общего состояния никто не видит.
 */
function разбудить(комната) {
  комната.версия++;
  const ждали = комната.ждущие;
  комната.ждущие = [];
  for (const ждущий of ждали) {
    clearTimeout(ждущий.таймер);
    /* Ожидание закончилось прямо сейчас — считаем это свежей весточкой
       от игрока. Иначе получалось так: пока опрос висел (до 25 секунд),
       время последнего запроса не двигалось, и в короткий промежуток между
       ответом и новым вопросом уборка успевала объявить игрока пропавшим.
       Сопернику при этом на миг вспыхивала тревожная надпись на ровном месте. */
    отметитьВремяЗапроса(комната, ждущий.ктоЯ);
    ждущий.позвать(показатьИгроку(комната, ждущий.ктоЯ));
  }
}

/**
 * Игрок спрашивает «что нового». Если он отстал от жизни (его версия
 * меньше нашей) — отвечаем сразу. Иначе придерживаем ответ, пока
 * что-нибудь не случится или не выйдет время.
 *
 * Возвращает функцию «я больше не жду» — её зовут, если игрок отвалился.
 */
function ждатьНовостей(комната, ктоЯ, версияИгрока, сколькоЖдать, позвать) {
  отметитьЖизнь(комната, ктоЯ);

  const известное = Number(версияИгрока);
  if (!Number.isFinite(известное) || известное < комната.версия) {
    позвать(показатьИгроку(комната, ктоЯ));
    return function () {};
  }

  const ждущий = { ктоЯ: ктоЯ, позвать: позвать, таймер: null };
  ждущий.таймер = setTimeout(function () {
    убратьИзЖдущих(комната, ждущий);
    // Время вышло, новостей нет — так и говорим, клиент спросит снова.
    позвать(null);
  }, сколькоЖдать);

  комната.ждущие.push(ждущий);

  /* Вернувшейся функцией сервер сообщает, что игрок отвалился.
     Если соединение оборвалось (закрыли вкладку, пропала сеть) —
     это видно сразу, ждать никаких сроков не нужно. */
  return function (этоОбрыв) {
    убратьИзЖдущих(комната, ждущий);
    if (этоОбрыв) отметитьПропажу(комната, ктоЯ);
  };
}

function убратьИзЖдущих(комната, ждущий) {
  clearTimeout(ждущий.таймер);
  const место = комната.ждущие.indexOf(ждущий);
  if (место !== -1) комната.ждущие.splice(место, 1);
  // Ожидание закончилось — отсчёт молчания идёт от этой секунды, а не от начала опроса.
  отметитьВремяЗапроса(комната, ждущий.ктоЯ);
}

/** Ждёт ли игрок новостей прямо сейчас — значит, соединение живо. */
function ждётСейчас(комната, ктоЯ) {
  return комната.ждущие.some(function (ждущий) { return ждущий.ктоЯ === ктоЯ; });
}

/** Пометить, что игрок пропал, и сразу сказать об этом сопернику. */
function отметитьПропажу(комната, ктоЯ) {
  const игрок = комната.игроки[ктоЯ];
  if (!игрок || игрок.ушёл || !игрок.наСвязи) return;
  if (ждётСейчас(комната, ктоЯ)) return;   // висит другой его опрос — значит, жив
  игрок.наСвязи = false;
  разбудить(комната);
}

/* ---------------------------------------------------------------------
   Ходы
   --------------------------------------------------------------------- */

/**
 * Запомнить, что случилось, — обезличенно: только место и название.
 *
 * «Кто» здесь — тот, с кем событие произошло, а не обязательно тот, кто
 * нажал кнопку. По этому месту потом подставляется имя в рассказе, и если
 * назвать здесь автора хода, игрок прочитает про себя чужое действие.
 */
function записатьСобытие(комната, ктоЯ, что) {
  комната.событие = { кто: ктоЯ, что: что };
  комната.номерСобытия++;
}

/**
 * Партия кончилась? Тогда комната переходит в «конец» и запоминает,
 * кто ходит первым в следующей партии: по обычаю «Дурака» — проигравший.
 * При ничьей никого не назначаем, пусть решает младший козырь.
 * В игре парами дураков двое — первым ходит любой из них, берём первого.
 */
function осмотретьПартию(комната) {
  if (комната.этап !== 'игра') return;
  if (!комната.партия || !комната.партия.завершена) return;

  комната.этап = 'конец';
  комната.сыграно++;
  const проигравшие = комната.партия.проигравшие || [];
  комната.дуракПрошлойПартии = проигравшие.length > 0 ? проигравшие[0] : null;
}

/**
 * Убрать из-за стола тех, кто ушёл насовсем.
 *
 * Зачем это нужно перед раздачей. Ушедший в конце партии остаётся числиться
 * за своим местом (по его пропуску ему ещё показывают итог), и без этой
 * уборки на реванше ему бы раздали карты — а ходить за него некому.
 * Партия встала бы намертво на первом же его ходе.
 *
 * Ботов это не касается: бот за столом остаётся, даже если он занял место
 * ушедшего посреди партии, — за него ходит сервер.
 */
function убратьУшедших(комната) {
  for (const место of занятыеМеста(комната)) {
    const игрок = комната.игроки[место];
    if (игрок.этоБот || !игрок.ушёл) continue;
    delete комната.игроки[место];
  }
  if (!комната.игроки[комната.хозяин]) передатьХозяина(комната);
}

/** Раздать карты всем, кто сидит за столом, и начать партию. */
function раздатьПартию(комната, ктоНачинает) {
  убратьУшедших(комната);
  const места = занятыеМеста(комната);
  комната.партия = партии.начатьПартию(ктоНачинает, {
    игроки: места,
    переводной: комната.переводной,
    парами: комната.парами,
    сложность: комната.уровеньБотов
  });
  комната.этап = 'игра';
  for (const место of места) {
    const игрок = комната.игроки[место];
    if (игрок && !игрок.этоБот) игрок.хочетЕщё = false;
  }
}

/**
 * Ход игрока: правила проверяют, комната запоминает событие и будит
 * остальных. Отказ никого не будит — он касается только того,
 * кто ошибся.
 *
 * Часть действий про карты вовсе не знает: «начать», «сыграть ещё»,
 * настройки стола и боты — это дела комнаты, и разбираются они здесь же,
 * до того как слово переходит правилам.
 */
function сделатьХод(комната, ктоЯ, намерение) {
  отметитьЖизнь(комната, ктоЯ);

  const действие = намерение && typeof намерение.действие === 'string' ? намерение.действие : '';

  switch (действие) {
    case 'ещё':         return предложитьЕщё(комната, ктоЯ);
    case 'начать':      return начатьПоКнопке(комната, ктоЯ);
    case 'настройки':   return поменятьНастройкиКомнаты(комната, ктоЯ, намерение);
    case 'бот':         return посадитьБота(комната, ктоЯ, намерение);
    case 'убрать-бота': return убратьБота(комната, ктоЯ);
    default: break;
  }

  if (комната.этап === 'ожидание') {
    return {
      принято: false,
      причина: комната.компания
        ? 'Партия ещё не началась: ждём, когда хозяин комнаты нажмёт «Начать»'
        : 'Соперник ещё не пришёл'
    };
  }

  /* Пропуск ушедшего продолжает работать — по нему ему показывают итог.
     Но ходить он уже не может: за столом на его месте либо никого нет,
     либо доигрывает бот, и два игрока на одном месте — это путаница. */
  const я = комната.игроки[ктоЯ];
  if (я && я.ушёл) {
    return { принято: false, причина: 'Вы вышли из этой партии — ходить в ней больше нельзя' };
  }

  const ответ = партии.сделатьХод(комната.партия, ктоЯ, намерение);
  if (!ответ.принято) return ответ;

  /* Событие приписываем не тому, кто нажал кнопку, а тому, с кем оно
     случилось. Разница видна на одном случае: подход заканчивает
     подкидывающий, а карты со стола забирает отбивавшийся. */
  записатьСобытие(комната, ответ.ктоСделал || ктоЯ, ответ.событие);
  /* Дальше это поле не нужно, а игроку его показывать нельзя: «ктоСделал» —
     внутреннее имя места за столом (вроде «бот-3»). Убираем сразу, чтобы оно
     физически не могло уехать наружу вместе с ответом. */
  delete ответ.ктоСделал;
  осмотретьПартию(комната);
  разбудить(комната);
  ботыДумают(комната);
  return ответ;
}

/* ---------------------------------------------------------------------
   Прихожая: пока карты не розданы, комнатой распоряжается создатель
   --------------------------------------------------------------------- */

/**
 * Общая проверка для всех действий прихожей: распоряжаться столом может
 * только хозяин комнаты и только пока партия не началась.
 * Вернёт отказ или null, если всё в порядке.
 */
function можноРаспоряжаться(комната, ктоЯ) {
  if (комната.этап === 'игра') {
    return { принято: false, причина: 'Партия уже идёт — стол теперь не поменять' };
  }
  if (комната.этап === 'конец') {
    return {
      принято: false,
      причина: 'Эта партия закончена. Нажмите «Сыграть ещё» — стол останется прежним'
    };
  }
  if (ктоЯ !== комната.хозяин) {
    return { принято: false, причина: 'Стол собирает тот, кто создал комнату' };
  }
  return null;
}

/* Пометка «комната.компания = true» ниже стоит в каждом действии прихожей,
   и вот почему. Пока хозяин ничего не трогал, комната остаётся прежней
   комнатой на двоих: друг вошёл — карты розданы сами, как было всегда.
   Но раз стол собирают руками (поменяли правила, посадили бота, нажали
   «Начать»), сама собой партия начинаться уже не должна — её начинает
   человек. Обратной дороги нет, да она и не нужна. */

/** Хозяин поменял правила игры или число мест за столом. */
function поменятьНастройкиКомнаты(комната, ктоЯ, намерение) {
  const нельзя = можноРаспоряжаться(комната, ктоЯ);
  if (нельзя) return нельзя;

  if (!применитьНастройки(комната, намерение)) {
    return { принято: false, причина: 'Не понял, что именно поменять за столом' };
  }
  комната.компания = true;
  записатьСобытие(комната, ктоЯ, 'настройки');
  разбудить(комната);
  return { принято: true, событие: 'настройки' };
}

/**
 * Можно ли раздвинуть стол на одно место ради нового бота.
 *
 * Раздвигаем только в одном случае: человек ни разу не называл число мест,
 * то есть за столом стоит начальная двойка — не выбор, а то, с чего комната
 * начинается. Тогда «Посадить бота» в обычной игре вдвоём работает как
 * раньше: стол растёт под компанию сам.
 *
 * Как только число мест названо (выбрали «Сколько играет» или включили игру
 * парами), оно становится законом. Раньше стол раздвигался всегда, и выходило
 * вот что: человек выбрал стол на четверых, нажал «Посадить бота» лишний раз
 * — и молча получил пятерых, а потом шестерых. В парной игре это ломало
 * партию совсем: начать вчетвером уже нельзя, а виноватым выглядит игрок,
 * который ничего, кроме числа ботов, не менял.
 */
function можноРаздвинутьСтол(комната) {
  if (комната.местВыбрали) return false;              // выбранное число мест не трогаем
  if (комната.парами) return false;                   // парная игра бывает только вчетвером
  return комната.мест < партии.МАКС_ИГРОКОВ;
}

/**
 * Почему бот не сел — человеческими словами, с подсказкой, что делать.
 * Причина всегда одна (мест нет), а вот выход из положения разный,
 * поэтому и говорим по-разному.
 */
function почемуБотуНекудаСесть(комната) {
  if (комната.парами) {
    return 'Игра парами бывает только вчетвером, и все четыре места уже заняты. ' +
      'Хотите играть большим кругом — сначала выключите игру парами';
  }
  if (комната.мест >= партии.МАКС_ИГРОКОВ) {
    return 'За столом нет свободных мест: больше шестерых не садится';
  }
  return 'Свободных мест нет: за столом их ' + комната.мест +
    ', столько вы и выбрали. Хотите играть большим кругом — ' +
    'поменяйте «Сколько играет»';
}

/** Посадить на свободное место бота. */
function посадитьБота(комната, ктоЯ, намерение) {
  const нельзя = можноРаспоряжаться(комната, ктоЯ);
  if (нельзя) return нельзя;

  комната.компания = true;
  if (!свободноеМесто(комната) && можноРаздвинутьСтол(комната)) комната.мест++;

  const место = свободноеМесто(комната);
  if (!место) {
    return { принято: false, причина: почемуБотуНекудаСесть(комната) };
  }

  /* Уровень отдельного бота проверяем тем же списком: сюда приходит третья
     дорога к тому же полю, и без проверки любая строка легла бы боту в память
     и досталась правилам вместо уровня. Не назвали или назвали непонятное —
     бот играет так же, как весь стол. */
  const уровень = уровеньИзСписка(намерение.уровень) || комната.уровеньБотов;
  комната.игроки[место] = новыйБот(место, уровень);
  записатьСобытие(комната, ктоЯ, 'посадили-бота');
  разбудить(комната);
  return { принято: true, событие: 'посадили-бота' };
}

/** Убрать из-за стола последнего посаженного бота. */
function убратьБота(комната, ктоЯ) {
  const нельзя = можноРаспоряжаться(комната, ктоЯ);
  if (нельзя) return нельзя;

  const боты = занятыеМеста(комната).filter(function (место) {
    return комната.игроки[место].этоБот;
  });
  if (боты.length === 0) {
    return { принято: false, причина: 'За столом нет ни одного бота' };
  }

  delete комната.игроки[боты[боты.length - 1]];

  /* Стол, который раздвинулся сам, сам же и ужимается. Иначе получалось
     обидное: посадил бота — «играют трое», убрал его — по-прежнему «играют
     трое», только одно место пустое, и человек не понимает, что он сделал.
     Стол, число мест которого человек назвал сам, не трогаем: пустое место
     там оставлено нарочно — под друга, который вот-вот войдёт. */
  if (!комната.местВыбрали) {
    комната.мест = Math.max(партии.МИН_ИГРОКОВ, докудаЗанятСтол(комната));
  }

  записатьСобытие(комната, ктоЯ, 'убрали-бота');
  разбудить(комната);
  return { принято: true, событие: 'убрали-бота' };
}

/**
 * Почему парная игра сейчас не начнётся — и что делать.
 *
 * Совет обязан зависеть от того, много за столом народу или мало. Раньше
 * он был один на оба случая («Посадите ботов или выключите игру парами»),
 * и при пятерых за столом получалась насмешка: чтобы играть вчетвером,
 * человеку предлагали посадить ещё одного.
 */
function чтоНеТакДляПарнойИгры(комната, занято) {
  const начало = 'Игра парами бывает только вчетвером, а за столом ' + занято.length + '. ';

  if (занято.length < партии.ИГРОКОВ_В_ПАРАХ) {
    return начало + 'Позовите друга по коду или посадите бота — или выключите игру парами';
  }

  /* Народу больше четырёх. Убрать лишнего можно только если это бот:
     выгнать человека из-за стола хозяин не может, у него такой кнопки нет.
     Поэтому людям за столом честно советуем другое — выключить игру парами. */
  const естьБоты = занято.some(function (место) { return комната.игроки[место].этоБот; });
  return начало + (естьБоты
    ? 'Уберите лишнего бота или выключите игру парами'
    : 'Выключите игру парами — или пусть кто-то один выйдет из комнаты');
}

/**
 * «Начать» — карты раздаются. Кнопка есть только у хозяина комнаты:
 * ему видно, все ли друзья уже подошли, а серверу — нет.
 */
function начатьПоКнопке(комната, ктоЯ) {
  const нельзя = можноРаспоряжаться(комната, ктоЯ);
  if (нельзя) return нельзя;

  const занято = занятыеМеста(комната);
  if (занято.length < партии.МИН_ИГРОКОВ) {
    return {
      принято: false,
      причина: 'За столом пока только вы. Позовите друга по коду или посадите бота'
    };
  }
  /* Парная игра бывает только вчетвером. Молча превращать её в обычную
     нечестно: человек выбирал одно, а получил бы другое, — поэтому
     говорим прямо и даём поправить. */
  if (комната.парами && занято.length !== партии.ИГРОКОВ_В_ПАРАХ) {
    return { принято: false, причина: чтоНеТакДляПарнойИгры(комната, занято) };
  }

  комната.компания = true;
  раздатьПартию(комната, null);
  записатьСобытие(комната, ктоЯ, 'начали');
  разбудить(комната);
  ботыДумают(комната);
  return { принято: true, событие: 'начали' };
}

/* ---------------------------------------------------------------------
   Боты ходят на сервере
   --------------------------------------------------------------------- */

/** Отменить отложенный ход бота, если он был назначен. */
function отменитьХодБота(комната) {
  if (!комната.таймерБота) return;
  clearTimeout(комната.таймерБота);
  комната.таймерБота = null;
}

/**
 * Если очередь дошла до бота — назначить его ход через небольшую паузу.
 *
 * Пауза нужна для людей: карты, падающие на стол мгновенно и все разом,
 * читаются как «что-то произошло, а что — непонятно». За эти доли секунды
 * игрок успевает увидеть каждый ход отдельно.
 *
 * Ход бота делается ЗДЕСЬ, на сервере, а не в чьём-то браузере. Иначе
 * картина у игроков разошлась бы: у одного бот уже сходил, у другого ещё
 * нет, а если «ведущий» потеряет связь — партия встанет навсегда.
 */
function ботыДумают(комната) {
  отменитьХодБота(комната);
  if (комната.этап !== 'игра') return;

  const место = партии.чейХод(комната.партия);
  if (!место) return;
  const игрок = комната.игроки[место];
  if (!игрок || !игрок.этоБот) return;

  комната.таймерБота = setTimeout(function () {
    комната.таймерБота = null;
    сходитьЗаБота(комната, место);
  }, партии.ПАУЗА_БОТА);
  // Таймер не должен держать программу запущенной — как и у уборщика.
  if (комната.таймерБота.unref) комната.таймерБота.unref();
}

/** Один ход бота: сходить, рассказать всем и посмотреть, чья очередь дальше. */
function сходитьЗаБота(комната, место) {
  const игрок = комната.игроки[место];
  if (!игрок || !игрок.этоБот) return;
  if (комната.этап !== 'игра') return;

  const сделано = партии.ходЗаБота(комната.партия, место, игрок.уровень);
  if (!сделано) return;   // не его очередь: за это время что-то изменилось

  // Как и у живого игрока: карты со стола мог забрать не тот бот, что ходил.
  записатьСобытие(комната, сделано.ктоСделал || место, сделано.событие);
  осмотретьПартию(комната);
  разбудить(комната);
  ботыДумают(комната);   // за ботом может ходить другой бот
}

/**
 * Реванш. Каждый нажавший просто предлагает; как только согласились все,
 * кто ещё за столом, карты раздаются заново в той же комнате, с тем же
 * кодом и теми же пропусками. Отказ отдельной кнопкой не нужен:
 * кто не хочет играть, тот выходит, и остальные это увидят.
 *
 * Боты согласны всегда — спрашивать их не о чем.
 */
function предложитьЕщё(комната, ктоЯ) {
  if (комната.этап !== 'конец') {
    return { принято: false, причина: 'Партия ещё не закончена' };
  }

  const я = комната.игроки[ктоЯ];

  /* Сам уже вышел — звать некого и не за чем. Пропуск после выхода
     продолжает работать, и без этой проверки вышедший мог позвать на реванш:
     оставшийся видел бы «Друг зовёт сыграть ещё», а нажать не смог бы —
     ему бы ответили, что соперник вышел. */
  if (!я || я.ушёл) {
    return { принято: false, причина: 'Вы вышли из этой партии — чтобы сыграть ещё, начните новую' };
  }

  /* Остальные за столом — все, кроме меня и кроме ушедших людей.
     Бот считается сидящим всегда, даже если он занял место ушедшего:
     доиграть партию с ботами можно, а вот звать ушедшего человека — нет. */
  const остальные = занятыеМеста(комната)
    .filter(function (место) {
      if (место === ктоЯ) return false;
      const игрок = комната.игроки[место];
      return игрок.этоБот || !игрок.ушёл;
    })
    .map(function (место) { return комната.игроки[место]; });

  if (остальные.length === 0) {
    return { принято: false, причина: 'Соперник вышел из игры' };
  }

  я.хочетЕщё = true;

  const ждёмОтвета = остальные.filter(function (игрок) { return !игрок.хочетЕщё; });
  if (ждёмОтвета.length > 0) {
    // Ждём согласия остальных — пока это только предложение.
    записатьСобытие(комната, ктоЯ, 'зовёт');
    разбудить(комната);
    return { принято: true, событие: 'зовёт' };
  }

  // Согласны все — раздаём заново.
  раздатьПартию(комната, комната.дуракПрошлойПартии);
  записатьСобытие(комната, ктоЯ, 'реванш');
  разбудить(комната);
  ботыДумают(комната);
  return { принято: true, событие: 'реванш' };
}

/* ---------------------------------------------------------------------
   Уход и уборка
   --------------------------------------------------------------------- */

/**
 * Игрок сам вышел. Это не то же самое, что потеря связи: пропавшего партия
 * ждёт, и он может вернуться, а ушедшего ждать незачем — иначе остальные
 * будут бесконечно ждать хода того, кого уже нет.
 *
 * Что происходит дальше, зависит от того, сколько человек за столом:
 *
 *   — карты ещё не розданы: место просто освобождается, на него может сесть
 *     кто-то другой. Ушёл хозяин — комнатой распоряжается следующий;
 *   — за столом двое: партия заканчивается без победителя, как и раньше.
 *     Ни выигрыша, ни поражения тут нет — просто несостоявшаяся игра;
 *   — за столом трое и больше: место ушедшего занимает бот и доигрывает
 *     его картами. Так партия у остальных не рушится из-за одного человека,
 *     а сдавать его карты в отбой посреди подхода было бы нечестно
 *     к тем, кто на них рассчитывал.
 */
function выйти(комната, ктоЯ) {
  const игрок = комната.игроки[ктоЯ];
  if (!игрок) return;
  игрок.ушёл = true;
  игрок.наСвязи = false;
  игрок.хочетЕщё = false;   // ушедший никого уже не зовёт играть дальше
  комната.трогали = Date.now();

  if (комната.этап === 'ожидание') {
    delete комната.игроки[ктоЯ];
    if (ктоЯ === комната.хозяин) передатьХозяина(комната);
    if (комната.компания) записатьСобытие(комната, ктоЯ, 'ушёл-из-комнаты');
  } else if (комната.партия && !комната.партия.завершена) {
    if (комната.партия.игроки.length > партии.МИН_ИГРОКОВ) {
      игрок.этоБот = true;
      игрок.уровень = комната.уровеньБотов;
      /* Имя человека оставляем как есть. Раньше место переименовывалось
         в «Бот 2», и со стороны выглядело так, будто Пётр исчез, а вместо
         него из ниоткуда появился какой-то бот. На самом деле карты Петра
         никуда не делись — их просто доигрывает бот, и это ровно то, что
         должно быть видно: имя «Пётр», роль «бот», пометка «вышел». */
      игрок.хочетЕщё = true;              // бот всегда согласен играть дальше
      записатьСобытие(комната, ктоЯ, 'ушёл-бот');
    } else {
      /* Заканчиваем партию без победителя. Поле «результат» намеренно
         оставляем пустым — по нему клиент и поймёт, что дело не в картах. */
      комната.партия.завершена = true;
      комната.партия.результат = null;
      комната.партия.проигравшие = [];
      комната.этап = 'конец';
      записатьСобытие(комната, ктоЯ, 'ушёл');
    }
  }

  разбудить(комната);
  ботыДумают(комната);   // если ход был за ушедшим, теперь сходит бот

  // Живых людей не осталось — держать комнату незачем.
  if (людиЗаСтолом(комната).length === 0) удалитьКомнату(комната.код);
}

/**
 * Хозяин ушёл из прихожей — распоряжаться столом становится следующий
 * по кругу. Иначе комната зависла бы навсегда: начать партию некому,
 * а вошедшие сидели бы и ждали кнопки, которой ни у кого нет.
 */
function передатьХозяина(комната) {
  const люди = людиЗаСтолом(комната);
  комната.хозяин = люди.length > 0 ? люди[0] : партии.ПЕРВЫЙ;
}

/** Убрать комнату и отпустить всех, кто ещё висит на опросе. */
function удалитьКомнату(код) {
  const комната = комнаты.get(код);
  if (!комната) return;
  отменитьХодБота(комната);   // ботам в убранной комнате ходить некуда
  const ждали = комната.ждущие;
  комната.ждущие = [];
  for (const ждущий of ждали) {
    clearTimeout(ждущий.таймер);
    ждущий.позвать(null);
  }
  комнаты.delete(код);
  запомнитьУбранныйКод(код);
}

/**
 * Запомнить код убранной комнаты — ненадолго и без всяких подробностей.
 * Нужно только затем, чтобы опоздавшему другу ответить «партия закрылась»
 * вместо «такого кода нет» и не записать ему штрафную неудачу.
 */
function запомнитьУбранныйКод(код) {
  // Держим память ограниченной: самый старый код выкидываем.
  if (убранные.size >= ПОМНИМ_УБРАННЫХ_КОДОВ) {
    const самыйСтарый = убранные.keys().next();
    if (!самыйСтарый.done) убранные.delete(самыйСтарый.value);
  }
  убранные.delete(код);          // чтобы код встал в конец очереди по времени
  убранные.set(код, Date.now());
}

/** Выкинуть из памяти коды, убранные слишком давно. */
function забытьСтарыеКоды(время) {
  for (const [код, когда] of убранные) {
    // Map хранит записи по порядку добавления: как только дошли до свежей,
    // дальше все свежие — обходить остаток незачем.
    if (время - когда <= ПОМНИМ_УБРАННЫЙ_КОД) break;
    убранные.delete(код);
  }
}

/**
 * Обход всех комнат: отмечаем пропавших игроков и выбрасываем брошенные
 * комнаты. Вызывается по таймеру, но вынесен отдельно, чтобы проверка
 * могла позвать его руками и не ждать полминуты.
 */
function прибратьсяСейчас(сейчас) {
  const время = сейчас || Date.now();
  забытьСтарыеКоды(время);

  for (const [код, комната] of комнаты) {
    /* Комната, в которой карты ещё не розданы, живёт заметно меньше начатой
       партии: там пока ничего не потеряно, а места на сервере она занимает. */
    const срок = комната.этап === 'ожидание' ? ЖИЗНЬ_ПУСТОЙ_КОМНАТЫ : ЖИЗНЬ_БРОШЕННОЙ_КОМНАТЫ;
    if (время - комната.трогали > срок) {
      удалитьКомнату(код);
      continue;
    }

    /* Кто давно молчит и не ждёт новостей — тот потерял связь.
       Остальные узнают об этом сами, без действий со своей стороны.
       Ботов это не касается вовсе: у них нет ни связи, ни запросов. */
    let что_то_изменилось = false;
    const пропалиНасовсем = [];
    for (const ктоЯ of занятыеМеста(комната)) {
      const игрок = комната.игроки[ктоЯ];
      if (игрок.этоБот || игрок.ушёл) continue;
      if (ждётСейчас(комната, ктоЯ)) continue;   // держит открытый опрос — жив

      const молчит = время - игрок.последнийЗапрос;

      // Молчит так долго, что ждать его дальше бессмысленно.
      if (молчит > ПРОПАЛ_НАСОВСЕМ) {
        пропалиНасовсем.push(ктоЯ);
        continue;
      }

      if (игрок.наСвязи && молчит > МОЛЧАНИЕ_ЭТО_ОБРЫВ) {
        игрок.наСвязи = false;
        что_то_изменилось = true;
      }
    }

    /* Пропавшего насовсем выводим тем же путём, что и того, кто нажал
       «выйти»: за столом на двоих партия закрывается без победителя,
       а в компании его место занимает бот, и остальные играют дальше.
       Разбудить остальных «выйти» умеет само, отдельно звать не надо. */
    if (пропалиНасовсем.length) {
      for (const ктоЯ of пропалиНасовсем) выйти(комната, ктоЯ);
      continue;
    }

    if (что_то_изменилось) разбудить(комната);
  }
}

let уборщик = null;

/** Запустить уборку по таймеру. Таймер не держит программу запущенной. */
function запуститьУборку() {
  if (уборщик) return;
  уборщик = setInterval(function () { прибратьсяСейчас(); }, УБОРКА_КАЖДЫЕ);
  if (уборщик.unref) уборщик.unref();
}

function остановитьУборку() {
  if (!уборщик) return;
  clearInterval(уборщик);
  уборщик = null;
}

/** Сколько комнат сейчас живо — для странички «сервер работает». */
function сколькоКомнат() {
  return комнаты.size;
}

