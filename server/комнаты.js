/** Случайный код из безопасного алфавита. Случайность берём криптостойкую. */
function новыйКод() {
  let код = '';
  const байты = крипто.randomBytes(ДЛИНА_КОДА);
  for (let i = 0; i < ДЛИНА_КОДА; i++) {
    код += АЛФАВИТ_КОДА[байты[i] % АЛФАВИТ_КОДА.length];
  }
  return код;
}

/**
 * Код, которого сейчас нет ни у одной живой комнаты.
 * Не нашли за 200 попыток — возвращаем null.
 *
 * Раньше на этот случай выдавался код двойной длины, но в поле ввода
 * помещается только четыре-шесть знаков: такой код игрок просто не смог бы
 * набрать. Честный отказ понятнее, чем комната, в которую нельзя войти.
 */
function свободныйКод() {
  for (let попытка = 0; попытка < 200; попытка++) {
    const код = новыйКод();
    if (!комнаты.has(код)) return код;
  }
  return null;
}

/**
 * Привести введённый код к общему виду: человек может набрать строчными,
 * с пробелом или дефисом посередине. Лишние символы просто выкидываем.
 */
function привестиКод(что) {
  if (typeof что !== 'string') return '';
  return что.toUpperCase().replace(/[^A-Z0-9]/g, '').slice(0, 12);
}

/** Пропуск — длинный случайный ключ, по нему игрок возвращается после обрыва. */
function новыйПропуск() {
  return крипто.randomBytes(16).toString('hex');
}

/* Метка попытки входа — постоянное имя открытой страницы, которое она
   присылает вместе с кодом комнаты. Нужна ровно за одним: отличить
   ПОВТОРНЫЙ запрос «войти» от второго настоящего гостя.

   Зачем. Сам по себе запрос «войти» ничем не приметен, и два одинаковых
   занимали два разных места — за столом появлялось «Пётр, Аня, Аня».
   Обычно призрак рассасывается сам (через три минуты молчания сервер его
   выводит), но до тех пор он делает две беды: партия ждёт его хода, а в игре
   парами он занимает четвёртое место, и настоящий друг войти уже не может.

   Почему именно метка страницы, а не что-то попроще. Адрес гостя не годится:
   за туннелем он у всех общий. Имя тоже: двое настоящих гостей могут
   оказаться тёзками. А метка у каждой открытой страницы своя.

   Слишком короткую метку не принимаем вовсе: метка — это ключ, по которому
   отдаётся уже выданный пропуск, и короткую её было бы слишком просто
   угадать. Настоящая страница присылает около двадцати знаков.
   Наружу метка не уходит никогда: показатьИгроку собирает ответ поле
   за полем, и этого поля там нет. */
const ДЛИНА_МЕТКИ = 64;
const МЕТКА_КОРОЧЕ_НЕ_БЫВАЕТ = 8;

/**
 * Привести метку к порядку: оставляем только буквы, цифры, дефис
 * и подчёркивание. Мусор, пустое и слишком короткое — это «метки не было»,
 * и тогда вход считается обычным, как со старой страницы.
 */
function привестиМетку(что) {
  if (typeof что !== 'string') return null;
  const чистая = что.replace(/[^0-9A-Za-z_-]/g, '').slice(0, ДЛИНА_МЕТКИ);
  return чистая.length >= МЕТКА_КОРОЧЕ_НЕ_БЫВАЕТ ? чистая : null;
}

