'use strict';

/* =====================================================================
   Обучение личин на партиях людей (копия igra2, решение владельца 03.10).

   Что делаем. Каждый ход ЧЕЛОВЕКА в сетевой партии записываем вместе
   с позицией, из которой он сделан. Когда партия кончилась, ходам
   победителя ставим «плюс», ничьей — половину. Так копится книга:
   позиция → ходы людей → сколько раз каждый ход привёл к победе.

   Как этим пользуется личина (server/личины.js). Перед своим ходом она
   смотрит книгу: в этой позиции люди уже играли и чаще побеждали после
   какого-то хода — с вероятностью ДОЛЯ_КНИГИ она сыграет его. Иначе
   ходит обычный серверный бот. Чем больше люди играют, тем больше
   позиций в книге и тем «человечнее» и сильнее личины в дебютах и
   знакомых положениях.

   Какие игры. Только те, где позиция целиком видна и описывается
   строкой: шашки и шахматы. В нардах ход зависит от кубиков, в картах —
   от скрытых карт; для них нужен свой разбор, это следующий шаг.

   Книга живёт в памяти и сохраняется в папку данных сервера файлом
   книга-ходов.json (не чаще раза в 30 секунд). Размер ограничен:
   лишние позиции с наименьшим числом партий выбрасываются.
   ===================================================================== */

const fs = require('fs');
const гдеДанные = require('./папка-данных.js');

const ИМЯ_ФАЙЛА = 'книга-ходов.json';
const ДОЛЯ_КНИГИ = 0.75;          // как часто личина берёт ход из книги, если он есть
const МИН_ПАРТИЙ = 2;             // ход должен встретиться хотя бы в двух партиях
const МИН_УСПЕХА = 0.5;           // и приводить к победе не реже, чем в половине
const ПОЗИЦИЙ_МАКС = 150000;      // на одну игру
const СОХРАНЯТЬ_РАЗ_В_МС = 30000;

/* ---------------------------------------------------------------------
   Переходники к играм: ключ позиции, ключ хода и сам ход для правил.
   --------------------------------------------------------------------- */
/* Правила грузим при старте: работающий сервер не должен читать js с диска позже. */
const ПравилаШахмат = require('../js/шахматы-правила.js');
function правилаШахмат() {
  return ПравилаШахмат;
}

const ИГРЫ = {
  'шашки': {
    позиция: function (партия) {
      const п = партия && партия.доска;
      if (!п || !Array.isArray(п.доска)) return null;
      return п.доска.join('') + '|' + п.ходит;
    },
    ход: function (намерение) {
      if (!намерение || намерение.действие !== 'ход') return null;
      const ход = {
        действие: 'ход', откуда: намерение.откуда, куда: намерение.куда,
        побитые: Array.isArray(намерение.побитые) ? намерение.побитые.slice() : undefined,
        станетДамкой: typeof намерение.станетДамкой === 'boolean' ? намерение.станетДамкой : undefined
      };
      if (ход.откуда === undefined || ход.куда === undefined) return null;
      return ход;
    },
    ключХода: function (ход) {
      return String(ход.откуда) + '-' + String(ход.куда) + ':' + (ход.побитые || []).join(',');
    }
  },
  'шахматы': {
    позиция: function (партия) {
      if (!партия || !партия.позиция) return null;
      try { return правилаШахмат().отпечатокПозиции(партия.позиция); } catch (сбой) { return null; }
    },
    ход: function (намерение) {
      if (!намерение || намерение.действие !== 'ход') return null;
      if (намерение.откуда === undefined || намерение.куда === undefined) return null;
      return { действие: 'ход', откуда: намерение.откуда, куда: намерение.куда, превращение: намерение.превращение };
    },
    ключХода: function (ход) {
      return String(ход.откуда) + '-' + String(ход.куда) + (ход.превращение ? '=' + ход.превращение : '');
    }
  }
};

function учится(игра) {
  return Object.prototype.hasOwnProperty.call(ИГРЫ, игра);
}

/* ---------------------------------------------------------------------
   Книга: игра → позиция → ключ хода → { ход, партий, очков }.
   --------------------------------------------------------------------- */
let книга = null;
let грязно = false;
let таймерСохранения = null;

function загрузить() {
  if (книга) return книга;
  книга = {};
  try {
    const сырое = JSON.parse(fs.readFileSync(гдеДанные.файл(ИМЯ_ФАЙЛА), 'utf8'));
    if (сырое && typeof сырое === 'object') книга = сырое;
  } catch (сбой) {
    книга = {};
  }
  return книга;
}

function сохранитьСейчас() {
  таймерСохранения = null;
  if (!грязно || !книга) return;
  грязно = false;
  try {
    fs.mkdirSync(гдеДанные.папка(), { recursive: true });
    const путь = гдеДанные.файл(ИМЯ_ФАЙЛА);
    fs.writeFileSync(путь + '.tmp', JSON.stringify(книга));
    fs.renameSync(путь + '.tmp', путь);
  } catch (сбой) {
    console.error('[обучение] не сохранилась книга ходов:', сбой && сбой.message);
  }
}

function сохранитьПотом() {
  грязно = true;
  if (таймерСохранения) return;
  таймерСохранения = setTimeout(сохранитьСейчас, СОХРАНЯТЬ_РАЗ_В_МС);
  if (таймерСохранения.unref) таймерСохранения.unref();
}

function подрезать(позиции) {
  const ключи = Object.keys(позиции);
  if (ключи.length <= ПОЗИЦИЙ_МАКС) return;
  const вес = function (к) {
    let в = 0;
    for (const х of Object.values(позиции[к])) в += х.партий;
    return в;
  };
  ключи.sort(function (а, б) { return вес(а) - вес(б); });
  for (const к of ключи.slice(0, ключи.length - ПОЗИЦИЙ_МАКС)) delete позиции[к];
}

/* ---------------------------------------------------------------------
   Запись.
   --------------------------------------------------------------------- */

/**
 * Снимок хода человека ДО того, как правила его применят: { позиция, ход,
 * ключХода, место }. Игра не учится или ход не тот — null.
 */
function снимок(игра, партия, место, намерение) {
  if (!учится(игра)) return null;
  const пер = ИГРЫ[игра];
  const позиция = пер.позиция(партия);
  const ход = пер.ход(намерение);
  if (!позиция || !ход) return null;
  return { позиция: позиция, ход: ход, ключХода: пер.ключХода(ход), место: место };
}

/**
 * Партия кончилась: записать в книгу все снимки этой партии.
 * исходМеста(место) → 'победа' | 'ничья' | 'поражение'.
 */
function закрепить(игра, снимки, исходМеста) {
  if (!учится(игра) || !Array.isArray(снимки) || снимки.length === 0) return 0;
  const все = загрузить();
  const позиции = все[игра] || (все[игра] = {});
  let записано = 0;
  for (const с of снимки) {
    const исход = исходМеста(с.место);
    if (исход !== 'победа' && исход !== 'ничья' && исход !== 'поражение') continue;
    const ходы = позиции[с.позиция] || (позиции[с.позиция] = {});
    const запись = ходы[с.ключХода] || (ходы[с.ключХода] = { ход: с.ход, партий: 0, очков: 0 });
    запись.партий += 1;
    запись.очков += исход === 'победа' ? 1 : исход === 'ничья' ? 0.5 : 0;
    записано++;
  }
  if (записано) {
    подрезать(позиции);
    сохранитьПотом();
  }
  return записано;
}

/* ---------------------------------------------------------------------
   Подсказка личине.
   --------------------------------------------------------------------- */

/**
 * Ход из книги для этой позиции или null. Берём ходы, сыгранные хотя бы
 * в МИН_ПАРТИЙ партиях и успешные не реже МИН_УСПЕХА; среди них — по
 * жребию, тем вероятнее, чем выше успех и чаще ход. С вероятностью
 * 1 − ДОЛЯ_КНИГИ книгу не смотрим вовсе: личина не робот с одной линией.
 */
function подсказка(игра, партия, случай) {
  if (!учится(игра)) return null;
  const жребий = typeof случай === 'function' ? случай : Math.random;
  if (жребий() >= ДОЛЯ_КНИГИ) return null;
  const позиция = ИГРЫ[игра].позиция(партия);
  if (!позиция) return null;
  const ходы = (загрузить()[игра] || {})[позиция];
  if (!ходы) return null;
  const годные = Object.values(ходы).filter(function (х) {
    return х.партий >= МИН_ПАРТИЙ && х.очков / х.партий >= МИН_УСПЕХА;
  });
  if (годные.length === 0) return null;
  const веса = годные.map(function (х) { return (х.очков / х.партий) * Math.sqrt(х.партий); });
  let бросок = жребий() * веса.reduce(function (а, б) { return а + б; }, 0);
  for (let i = 0; i < годные.length; i++) {
    бросок -= веса[i];
    if (бросок <= 0) return JSON.parse(JSON.stringify(годные[i].ход));
  }
  return JSON.parse(JSON.stringify(годные[годные.length - 1].ход));
}

/** Сколько позиций знает книга по игре (для проверок и /здоровье). */
function размер(игра) {
  return Object.keys(загрузить()[игра] || {}).length;
}

/** Только для проверок: забыть всё и начать с пустой книги. */
function забытьВсё() {
  книга = {};
  грязно = false;
}

module.exports = {
  учится: учится,
  снимок: снимок,
  закрепить: закрепить,
  подсказка: подсказка,
  размер: размер,
  сохранитьСейчас: сохранитьСейчас,
  забытьВсё: забытьВсё,
  ДОЛЯ_КНИГИ: ДОЛЯ_КНИГИ,
  МИН_ПАРТИЙ: МИН_ПАРТИЙ
};
