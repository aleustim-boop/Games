/* Метки собираются в регулярные выражения сервера без экранирования —
   поэтому годны только строчные латинские буквы. Опечатка в таблице
   должна уронить сервер при запуске, а не тихо открыть дыру в разборе. */
for (const строка of ИГРЫ) {
  if (строка.метка !== null && !/^[a-z]+$/.test(String(строка.метка))) {
    throw new Error('server/названия.js: метка игры «' + строка.игра + '» — «' + строка.метка +
      '», а годны только строчные латинские буквы');
  }
}

const ЗАПАСНАЯ = ИГРЫ[0];

/** Строка таблицы по слову игры; незнакомое слово — дурак. */
function словаИгры(игра) {
  for (const строка of ИГРЫ) {
    if (строка.игра === игра) return строка;
  }
  return ЗАПАСНАЯ;
}

/** Слово игры по метке из ссылки: 'nardy' → 'нарды'; незнакомая или пустая — ''. */
function играПоМетке(метка) {
  if (!метка) return '';
  for (const строка of ИГРЫ) {
    if (строка.метка && строка.метка === метка) return строка.игра;
  }
  return '';
}

/** Метка игры для ссылки: 'нарды' → 'nardy'; без метки или незнакомая — ''. */
function меткаИгры(игра) {
  for (const строка of ИГРЫ) {
    if (строка.игра === игра) return строка.метка || '';
  }
  return '';
}

/** Все метки игр по сети — для сборки регулярных выражений разбора ссылок.
 *  Метки — только латиница, экранировать в них нечего. */
function всеМетки() {
  return ИГРЫ.filter(function (строка) { return !!строка.метка; })
    .map(function (строка) { return строка.метка; });
}

/** Слова всех игр по сети, у которых есть метка, — по порядку таблицы. */
function сетевыеИгры() {
  return ИГРЫ.filter(function (строка) { return !!строка.метка; })
    .map(function (строка) { return строка.игра; });
}

module.exports = {
  ИГРЫ: ИГРЫ,
  ЗАПАСНАЯ: ЗАПАСНАЯ,
  словаИгры: словаИгры,
  играПоМетке: играПоМетке,
  меткаИгры: меткаИгры,
  всеМетки: всеМетки,
  сетевыеИгры: сетевыеИгры
};
