/* =====================================================================
   ОДНА ТАБЛИЦА ИГР НА СЕРВЕРЕ: метка в ссылке и слова о игре.

   Зачем. Раньше каждая часть сервера держала свой словарик игр
   (метки ссылок, название в письме знакомому, название в ленте бота),
   и новые игры в них не попадали: нарды и деберц читались как дурак,
   а ссылка «nardy_КОД» не узнавалась вовсе. Теперь всё про название
   игры берётся отсюда, и новая игра добавляется одной строкой.

   Поля строки:
     игра     — слово игры внутри сервера (как в комнате: комната.игра);
     метка    — латинское слово в начале startapp, те же слова, что
                МЕТКИ_ИГР в js/сеть.js; null — у игры нет игры по сети;
     страница — какую страницу открывает ссылка этой игры;
     название — именем, с заглавной: для кнопки «Сесть за стол: …»;
     вИгру    — «играть во что»: «в подкидного дурака», «в нарды»;
     заСтолом — «за вашим столом в …» (без «в»): у дурака «подкидного
                дурака», у остальных совпадает с вИгру без «в»;
     партия   — «партия в …» (без «в»): у дурака короче — «дурака»;
     вИгре    — «победа в чём»: «в подкидном дураке», «в нардах».

   Слова — закрытый набор: игра, которой тут нет, читается как дурак.
   Подставлять в письма что-то пришедшее снаружи нельзя.
   ===================================================================== */

