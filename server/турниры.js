'use strict';

/* =====================================================================
   Турниры по расписанию (план: штаб/план-турниры.md, этап Э1).

   Что здесь есть: расписание турнира дня (по Москве), запись участников,
   хранение в файле (Э1) и «арена»: подбор пар, очки, таблица, итог дня (Э2).

   Стадии дня: запись (с московской полуночи; записаться можно до 20:25) →
   идёт (20:00–20:30, сводим пары) → доигрыш (20:30–20:40, партии
   доигрываются, новых пар нет) → окончен. В день не из ТУРНИР_ДНИ —
   «нет турнира».

   Арена. Человек зовёт готовЖдать(номер, мс), пока ждёт пару. Подбор
   (подобратьПары) помечает свёденную пару ЗАНЯТОЙ: занятый больше не ждёт
   и снова не сводится, пока его не освободят. Освобождают: партияСыграна
   (обоих людей сразу), освободить(номер) — если стол пропал без итога,
   вернутьВОжидание(номер, мс) — если стол не удалось создать (человек
   встаёт обратно с прежним временем начала ожидания). Посадка личиной —
   снятьСОжидания(номер): тоже «занят». «Последний соперник» (чтобы не
   сводить тех же двоих подряд) записывается ТОЛЬКО в партияСыграна:
   несозданный стол его не портит.

   Договор по ид партии: поле «партия» у партияСыграна — строка, уникальная
   и после перезапуска сервера (например, ид турнира + номер партии стола +
   код стола). Повтор того же ид не засчитывается дважды, журнал лежит
   в файле. Необязательное поле «началоМс» (когда партия началась): начатая
   не раньше конца пар (20:30) не засчитывается.

   Запись на диск сразу (записать, партияСыграна, готовЖдать при первом
   входе): результат и запись нельзя потерять перезапуском.

   Время. Москва = UTC+3 круглый год, без перехода на летнее время.
   Всё считаем от UTC и сдвигаем на три часа САМИ. Пояс машины не
   участвует вообще: боевой сервер живёт по UTC, машина штаба — по +02:00,
   а турнир у всех в 20:00 по Москве. Поэтому в файле только методы
   getUTC*, а не getHours/getDate. Время всегда приходит доводом
   (сейчасМс) — проверка может крутить часы как хочет.

   Модуль чистый: из комнат и сервера ничего не require'ит. Подключение
   к серверу — Э4.
   ===================================================================== */

const fs = require('fs');
const гдеДанные = require('./папка-данных.js');

/** «1,3,5» → [1, 3, 5]; пусто или мусор — все семь дней. */
function разобратьДни(строка) {
  const дни = String(строка || '').split(',').map(function (с) { return Number(с.trim()); })
    .filter(function (н) { return Number.isInteger(н) && н >= 1 && н <= 7; });
  return дни.length > 0 ? дни : [1, 2, 3, 4, 5, 6, 7];
}

/* ---------------------------------------------------------------------
   Настройки (рекомендованные; решения владельца ещё не пришли)
   --------------------------------------------------------------------- */
const НАСТРОЙКИ = {
  игра: 'дурак',            // один на один
  началоЧас: 20,            // начало турнира, часы по Москве
  началоМинута: 0,
  длительностьМин: 30,      // сколько идёт турнир
  записьДоКонцаМин: 5,      // записаться можно до «конец минус столько» (20:25)
  /* Дни недели турнира по Москве: 1 = понедельник … 7 = воскресенье.
     Из ТУРНИР_ДНИ («1,3,5»); нет или не поняли — все дни. */
  дни: разобратьДни(process.env['ТУРНИР_ДНИ']),
  хранитьДней: 60,          // старые турниры с диска выбрасываем
  имяДлинаМакс: 40,
  /* Арена (Э2) */
  очкиПобеда: 2,
  очкиНичья: 1,
  очкиПоражение: 0,
  готовностьМс: 10 * 1000,        // «на экране»: подтверждение старше этого — человек пропал
  ждётДоЛичиныМс: 90 * 1000,      // сколько человек ждёт пару, прежде чем ему можно дать личину
  доигрышМин: 10                  // партии, начатые до конца, засчитываются ещё столько
};

const СДВИГ_МСК_МС = 3 * 60 * 60 * 1000;
const МИНУТА = 60 * 1000;
const СУТКИ = 24 * 60 * 60 * 1000;
const ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ = 2000;

/* ---------------------------------------------------------------------
   Время по Москве
   --------------------------------------------------------------------- */

/** Число с нулём впереди: 5 → «05». */
function дваЗнака(число) {
  return (число < 10 ? '0' : '') + число;
}

/** Год, месяц (0–11) и день по московским часам. */
function деньПоМоскве(мс) {
  const сдвинутая = new Date(мс + СДВИГ_МСК_МС);
  return {
    год: сдвинутая.getUTCFullYear(),
    месяц: сдвинутая.getUTCMonth(),
    день: сдвинутая.getUTCDate(),
    деньНедели: сдвинутая.getUTCDay() || 7    // 1 = понедельник … 7 = воскресенье
  };
}

/** Окно турнира того московского дня, в который попадает момент «мс». */
function окноДня(мс) {
  const д = деньПоМоскве(мс);
  /* Московские 20:00 = 17:00 UTC: три часа вычитаем сами. Date.UTC
     понимает и отрицательный час (перенос на прошлые сутки). */
  const началоМс = Date.UTC(д.год, д.месяц, д.день,
    НАСТРОЙКИ.началоЧас - 3, НАСТРОЙКИ.началоМинута);
  return {
    ид: НАСТРОЙКИ.игра + '-' + д.год + '-' + дваЗнака(д.месяц + 1) + '-' + дваЗнака(д.день),
    игра: НАСТРОЙКИ.игра,
    деньНедели: д.деньНедели,
    началоМс: началоМс,
    конецМс: началоМс + НАСТРОЙКИ.длительностьМин * МИНУТА
  };
}

/** Состояние турнира в момент «мс»: нет турнира / запись / идёт / доигрыш / окончен. */
function состояние(окно, мс) {
  if (НАСТРОЙКИ.дни.indexOf(окно.деньНедели) === -1) return 'нет турнира';
  if (мс >= окно.конецМс + НАСТРОЙКИ.доигрышМин * МИНУТА) return 'окончен';
  if (мс >= окно.конецМс) return 'доигрыш';
  if (мс >= окно.началоМс) return 'идёт';
  return 'запись';
}

function взятьВремя(сейчасМс) {
  return Number.isFinite(сейчасМс) ? сейчасМс : Date.now();
}

/* ---------------------------------------------------------------------
   Память и файл
   --------------------------------------------------------------------- */

/** ид → турнир {ид, игра, началоМс, конецМс, участники, пары}. Таблицу не храним: она считается из журнала «пары».
    участники: номер Telegram (строкой) → { имя, записанМс }. */
const турниры = new Map();

let папкаДанных = null;      // своя папка (проверкам); иначе — общая
let ужеЗагрузили = false;
let чтениеСломано = false;   // файл не прочитался по иной причине, чем «его нет»: поверх не пишем
let записьРазрешена = false;
let естьЧтоЗаписать = false;
let таймерЗаписи = null;
let этоЛичина = function () { return false; };

function файл() {
  return папкаДанных ? папкаДанных + '/турниры.json' : гдеДанные.файл('турниры.json');
}
function файлПокаПишем() { return файл() + '.пишем'; }
function файлБитый() { return файл() + '.битый'; }
function папкаФайла() { return папкаДанных || гдеДанные.папка(); }

function этоНомерИгрока(номер) {
  return Number.isInteger(номер) && номер > 0;
}

/** Имя игрока: строка, обрезанная по длине; пустое — «Игрок». */
function чистоеИмя(имя) {
  const строка = typeof имя === 'string' ? имя.replace(/\s+/g, ' ').trim() : '';
  return строка.slice(0, НАСТРОЙКИ.имяДлинаМакс) || 'Игрок';
}

/** Запись журнала партий годна: ид партии, два разных номера, понятный исход. */
function этоЗаписьПартии(з) {
  return !!з && typeof з === 'object' && typeof з.партия === 'string' && з.партия !== '' &&
    этоНомерИгрока(з.а) && этоНомерИгрока(з.б) && з.а !== з.б &&
    (з.исход === 'а' || з.исход === 'б' || з.исход === 'ничья') &&
    Array.isArray(з.личины) && Number.isFinite(з.мс);
}

/** Турнир с диска — поле за полем; негодный — null. */
function чистыйТурнир(сырой) {
  if (!сырой || typeof сырой !== 'object') return null;
  const началоМс = Number(сырой.началоМс);
  const конецМс = Number(сырой.конецМс);
  if (typeof сырой.ид !== 'string' || !Number.isFinite(началоМс) || !Number.isFinite(конецМс)) return null;
  const участники = {};
  const сырыеУчастники = сырой.участники && typeof сырой.участники === 'object' ? сырой.участники : {};
  for (const ключ of Object.keys(сырыеУчастники)) {
    if (!этоНомерИгрока(Number(ключ))) continue;
    const п = сырыеУчастники[ключ] || {};
    const записанМс = Number(п.записанМс);
    участники[ключ] = { имя: чистоеИмя(п.имя), записанМс: Number.isFinite(записанМс) ? записанМс : началоМс };
  }
  return {
    ид: сырой.ид.slice(0, 60),
    игра: typeof сырой.игра === 'string' ? сырой.игра.slice(0, 40) : НАСТРОЙКИ.игра,
    началоМс: началоМс,
    конецМс: конецМс,
    участники: участники,
    /* Журнал сыгранных партий (Э2): из него считается таблица. С диска берём
       только записи с понятными номерами и исходом. */
    пары: Array.isArray(сырой.пары) ? сырой.пары.filter(этоЗаписьПартии) : []
  };
}

/** Прочитать файл. Нет файла — чистый лист. В .битый откладываем ТОЛЬКО файл,
    который прочитался, но не разобрался как JSON. Иная ошибка чтения (доступ,
    занят) — начинаем с пустого в памяти, файл не трогаем и поверх него не пишем. */
function загрузить() {
  if (ужеЗагрузили) return;
  ужеЗагрузили = true;
  let прочитанное = null;
  let текст = null;
  try {
    текст = fs.readFileSync(файл(), 'utf8');
  } catch (сбой) {
    if (сбой && сбой.code !== 'ENOENT') чтениеСломано = true;
  }
  if (текст !== null) {
    try {
      прочитанное = JSON.parse(текст);
    } catch (_) {
      try { fs.renameSync(файл(), файлБитый()); } catch (__) { /* начнём с чистого листа */ }
    }
  }
  if (прочитанное && прочитанное.турниры && typeof прочитанное.турниры === 'object') {
    for (const ид of Object.keys(прочитанное.турниры)) {
      const турнир = чистыйТурнир(прочитанное.турниры[ид]);
      if (турнир) турниры.set(ид, турнир);
    }
  }
  прибраться(Date.now());
}

/** Выбросить турниры старше срока хранения. */
function прибраться(мс) {
  const самоеСтарое = мс - НАСТРОЙКИ.хранитьДней * СУТКИ;
  for (const [ид, турнир] of турниры) {
    if (турнир.конецМс < самоеСтарое) турниры.delete(ид);
  }
}

function записатьСейчас() {
  if (чтениеСломано) return;
  const всё = {};
  for (const [ид, турнир] of турниры) всё[ид] = турнир;
  try {
    fs.mkdirSync(папкаФайла(), { recursive: true });
    fs.writeFileSync(файлПокаПишем(), JSON.stringify({ турниры: всё }), 'utf8');
    fs.renameSync(файлПокаПишем(), файл());
    естьЧтоЗаписать = false;   // снимаем, только когда файл правда на месте
  } catch (сбой) {
    /* Не записалось — флаг остаётся, следующая попытка (или дописать) повторит. */
  }
}

function записатьПогодя() {
  естьЧтоЗаписать = true;
  if (!записьРазрешена || таймерЗаписи !== null) return;
  таймерЗаписи = setTimeout(function () {
    таймерЗаписи = null;
    if (естьЧтоЗаписать) записатьСейчас();
  }, ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ);
  if (таймерЗаписи.unref) таймерЗаписи.unref();
}

/** Записать сразу, не дожидаясь таймера (запись и итог партии терять нельзя). */
function записатьСрочно() {
  естьЧтоЗаписать = true;
  if (!записьРазрешена) return;
  if (таймерЗаписи !== null) {
    clearTimeout(таймерЗаписи);
    таймерЗаписи = null;
  }
  записатьСейчас();
}

/**
 * Разрешить запись на диск (только настоящий сервер и проверки).
 * папка — необязательно: своя папка данных вместо общей.
 */
function включитьЗапись(папка) {
  if (typeof папка === 'string' && папка) папкаДанных = папка;
  записьРазрешена = true;
  if (естьЧтоЗаписать) записатьПогодя();
}

/** Записать немедленно, если было что (остановка сервера, проверки). */
function дописать() {
  if (таймерЗаписи !== null) {
    clearTimeout(таймерЗаписи);
    таймерЗаписи = null;
  }
  if (записьРазрешена && естьЧтоЗаписать) записатьСейчас();
}

/** Подключить помощников сервера. этоЛичина(номер) → true: номер — личина. */
function подключить(помощники) {
  if (помощники && typeof помощники.этоЛичина === 'function') этоЛичина = помощники.этоЛичина;
}

