/** Турнир того московского дня, в котором лежит момент «сейчасМс». */
function турнирДня(сейчасМс) {
  const мс = взятьВремя(сейчасМс);
  const окно = окноДня(мс);
  return {
    ид: окно.ид,
    игра: окно.игра,
    началоМс: окно.началоМс,
    конецМс: окно.конецМс,
    состояние: состояние(окно, мс)
  };
}

/** Турнир этого окна; нет такого — заводим пустой. */
function взятьТурнир(окно, мс) {
  let турнир = турниры.get(окно.ид);
  if (!турнир) {
    турнир = {
      ид: окно.ид, игра: окно.игра, началоМс: окно.началоМс, конецМс: окно.конецМс,
      участники: {}, пары: []
    };
    турниры.set(окно.ид, турнир);
    прибраться(мс);
  }
  return турнир;
}

/** Записать человека на турнир дня: { ок: true } или { ок: false, почему }. */
function записать(номер, имя, сейчасМс) {
  загрузить();
  if (!этоНомерИгрока(номер)) return { ок: false, почему: 'Не удалось понять, кто вы. Откройте игру из Telegram.' };
  if (этоЛичина(номер)) return { ок: false, почему: 'Этот игрок не может записаться на турнир.' };
  const мс = взятьВремя(сейчасМс);
  const окно = окноДня(мс);
  const сейчасЖе = состояние(окно, мс);
  if (сейчасЖе === 'нет турнира') return { ок: false, почему: 'Сегодня турнира нет.' };
  if (сейчасЖе === 'доигрыш' || сейчасЖе === 'окончен') return { ок: false, почему: 'Сегодняшний турнир уже закончился. Завтра будет новый.' };
  if (мс >= окно.конецМс - НАСТРОЙКИ.записьДоКонцаМин * МИНУТА) {
    return { ок: false, почему: 'Запись закрыта: до конца турнира осталось меньше ' + НАСТРОЙКИ.записьДоКонцаМин + ' минут. Завтра будет новый.' };
  }

  const турнир = взятьТурнир(окно, мс);
  const ключ = String(номер);
  if (турнир.участники[ключ]) return { ок: true, уже: true };   // повторная запись не задваивает
  турнир.участники[ключ] = { имя: чистоеИмя(имя), записанМс: мс };
  записатьСрочно();
  return { ок: true };
}

/** Снять запись. Только до начала: когда турнир идёт, очки уже копятся. */
function отписать(номер, сейчасМс) {
  загрузить();
  const мс = взятьВремя(сейчасМс);
  const окно = окноДня(мс);
  const сейчасЖе = состояние(окно, мс);
  if (сейчасЖе === 'идёт' || сейчасЖе === 'доигрыш' || сейчасЖе === 'окончен') {
    return { ок: false, почему: 'Турнир уже начался: запись снять нельзя.' };
  }
  const турнир = турниры.get(окно.ид);
  const ключ = String(номер);
  if (!турнир || !турнир.участники[ключ]) return { ок: false, почему: 'Вы не записаны на турнир.' };
  delete турнир.участники[ключ];
  записатьПогодя();
  return { ок: true };
}

/** Записан ли человек на турнир дня. */
function записан(номер, сейчасМс) {
  загрузить();
  const турнир = турниры.get(окноДня(взятьВремя(сейчасМс)).ид);
  return !!(турнир && турнир.участники[String(номер)]);
}

/** Участники турнира по ид — ТОЛЬКО внутри сервера (там номера Telegram). */
function участники(ид) {
  загрузить();
  const турнир = турниры.get(ид);
  if (!турнир) return [];
  return Object.keys(турнир.участники).map(function (ключ) {
    return { номер: Number(ключ), имя: турнир.участники[ключ].имя };
  });
}

/* ---------------------------------------------------------------------
   Арена (Э2): кто ждёт пару, подбор, очки, таблица, итог дня.
   Ожидание живёт только в памяти (перезапуск его теряет — люди снова
   нажмут «готов»). Журнал партий — в файле, из него считается таблица.
   --------------------------------------------------------------------- */

/** ид турнира → { ждут: номер → {сМс, видянМс}, занятые: номер → {сМс} (сведены в пару
    или сидят с личиной, ждать не могут), последний: номер → номер соперника }. */
const ожидания = new Map();

function ожиданиеТурнира(ид) {
  let ож = ожидания.get(ид);
  if (!ож) {
    /* Начался новый день: ожидания прошлых турниров больше не нужны. */
    ожидания.clear();
    ож = { ждут: new Map(), занятые: new Map(), последний: new Map() };
    ожидания.set(ид, ож);
  }
  return ож;
}

/** Подтверждение «я на экране» свежее: человек не пропал. */
function наСвязи(запись, мс) {
  return мс - запись.видянМс <= НАСТРОЙКИ.готовностьМс;
}

/** Турнир идёт сию минуту — { окно, турнир, ож }; иначе null. */
function идущийТурнир(мс) {
  const окно = окноДня(мс);
  if (состояние(окно, мс) !== 'идёт') return null;
  const турнир = взятьТурнир(окно, мс);
  return { окно: окно, турнир: турнир, ож: ожиданиеТурнира(окно.ид) };
}

/** Ждущие люди на связи, дольше ждущие первыми. */
function ждущиеНаСвязи(ож, мс) {
  const список = [];
  for (const [номер, запись] of ож.ждут) {
    if (наСвязи(запись, мс)) список.push({ номер: номер, сМс: запись.сМс });
  }
  список.sort(function (x, y) { return x.сМс - y.сМс || x.номер - y.номер; });
  return список;
}

/**
 * Человек на экране турнира, свободен и ищет пару. Звать, пока он ждёт
 * (опрос чаще, чем раз в десять секунд). Не записан — запишем (войти можно
 * и без записи, пока турнир идёт). Вернёт { ок: true } или { ок: false, почему }.
 */
function готовЖдать(номер, сейчасМс, имя) {
  загрузить();
  if (!этоНомерИгрока(номер)) return { ок: false, почему: 'Не удалось понять, кто вы. Откройте игру из Telegram.' };
  if (этоЛичина(номер)) return { ок: false, почему: 'Этот игрок не может участвовать в турнире.' };
  const мс = взятьВремя(сейчасМс);
  const идёт = идущийТурнир(мс);
  if (!идёт) return { ок: false, почему: 'Турнир сейчас не идёт.' };
  const ключ = String(номер);
  if (!идёт.турнир.участники[ключ]) {
    идёт.турнир.участники[ключ] = { имя: чистоеИмя(имя), записанМс: мс };
    записатьСрочно();
  }
  if (идёт.ож.занятые.has(номер)) return { ок: false, занят: true, почему: 'Вы сейчас играете партию турнира.' };
  const запись = идёт.ож.ждут.get(номер);
  if (запись && наСвязи(запись, мс)) {
    запись.видянМс = мс;                  // всё ещё ждёт — отсчёт ожидания идёт дальше
  } else {
    идёт.ож.ждут.set(номер, { сМс: мс, видянМс: мс });   // пропадал или только пришёл — отсчёт заново
  }
  return { ок: true };
}

/** Человека посадили с личиной: больше не ждёт и считается занятым, пока его не освободят. */
function снятьСОжидания(номер, сейчасМс) {
  const ож = ожидания.get(окноДня(взятьВремя(сейчасМс)).ид);
  if (!ож) return;
  const запись = ож.ждут.get(номер);
  ож.занятые.set(номер, { сМс: запись ? запись.сМс : взятьВремя(сейчасМс) });
  ож.ждут.delete(номер);
}

/** Освободить занятого (стол пропал без итога): ждать он начнёт сам, снова позвав готовЖдать. */
function освободить(номер, сейчасМс) {
  const ож = ожидания.get(окноДня(взятьВремя(сейчасМс)).ид);
  if (ож) ож.занятые.delete(номер);
}

/**
 * Стол не создали — человек встаёт обратно в ожидание с ПРЕЖНИМ временем
 * начала ожидания (его очередь и отсчёт до личины не теряются).
 */
function вернутьВОжидание(номер, сейчасМс) {
  const мс = взятьВремя(сейчасМс);
  const ож = ожидания.get(окноДня(мс).ид);
  const занятой = ож && ож.занятые.get(номер);
  if (!занятой) return;
  ож.занятые.delete(номер);
  ож.ждут.set(номер, { сМс: занятой.сМс, видянМс: мс });
}

/**
 * Свести ждущих людей в пары. Забирает их из ожидания и помечает занятыми.
 * Не на связи (не подтвердили готовность) — в подбор не идут. Дольше
 * ждущие первыми; тех же двоих подряд не сводим, если есть другой вариант.
 * Вернёт [{ а, б }] — номера Telegram, ТОЛЬКО внутри сервера.
 */
function подобратьПары(сейчасМс) {
  загрузить();
  const мс = взятьВремя(сейчасМс);
  const идёт = идущийТурнир(мс);
  if (!идёт) return [];
  const ож = идёт.ож;
  const свободные = ждущиеНаСвязи(ож, мс).map(function (з) { return з.номер; });
  const пары = [];
  while (свободные.length >= 2) {
    const а = свободные.shift();
    let место = свободные.findIndex(function (б) {
      return ож.последний.get(а) !== б && ож.последний.get(б) !== а;
    });
    if (место === -1) место = 0;          // другого варианта нет — сводим снова
    const б = свободные.splice(место, 1)[0];
    пары.push({ а: а, б: б });
    /* Пара занята до итога; «последнего соперника» здесь не пишем: стол мог не создаться. */
    ож.занятые.set(а, { сМс: ож.ждут.get(а).сМс });
    ож.занятые.set(б, { сМс: ож.ждут.get(б).сМс });
    ож.ждут.delete(а);
    ож.ждут.delete(б);
  }
  return пары;
}

/**
 * Кому нужен запасной соперник (личина): ждёт пару дольше 90 с, а второго
 * ждущего человека, с которым его можно свести, нет (двое ждущих — их сведёт
 * подбор, пары из людей всегда раньше личины). Сколько всего людей в турнире —
 * не важно: даже один человек на арене получает личину.
 * Вернёт [номер] — серверу осталось посадить личину и вызвать снятьСОжидания.
 */
function нуженЗапасной(сейчасМс) {
  загрузить();
  const мс = взятьВремя(сейчасМс);
  const идёт = идущийТурнир(мс);
  if (!идёт) return [];
  const ждущие = ждущиеНаСвязи(идёт.ож, мс);
  if (ждущие.length !== 1) return [];
  return ждущие.filter(function (з) {
    return мс - з.сМс > НАСТРОЙКИ.ждётДоЛичиныМс;
  }).map(function (з) { return з.номер; });
}

/** Очки за исход партии для сторон «а» и «б». */
function очкиЗаИсход(исход) {
  if (исход === 'а') return { а: НАСТРОЙКИ.очкиПобеда, б: НАСТРОЙКИ.очкиПоражение };
  if (исход === 'б') return { а: НАСТРОЙКИ.очкиПоражение, б: НАСТРОЙКИ.очкиПобеда };
  return { а: НАСТРОЙКИ.очкиНичья, б: НАСТРОЙКИ.очкиНичья };
}

/**
 * Итог партии. Звать только серверу (по событию 'итог' комнат).
 * партия = { партия: ид партии (строка), а, б: номера, исход: 'а'|'б'|'ничья',
 * личинаЛи: true, если одна из сторон личина, имяА, имяБ, началоМс — необязательно }.
 * Принимаем с начала турнира и до конца доигрыша; партию, начатую не раньше
 * конца пар (20:30), не засчитываем; тот же ид партии дважды не засчитываем.
 * Личине очки не пишутся: она не в таблице. Принятая партия освобождает обоих людей.
 */
function партияСыграна(ид, данные, сейчасМс) {
  загрузить();
  const мс = взятьВремя(сейчасМс);
  const турнир = турниры.get(ид);
  if (!турнир) return { ок: false, почему: 'Такого турнира нет.' };
  if (мс < турнир.началоМс) return { ок: false, почему: 'Турнир ещё не начался.' };
  if (мс >= турнир.конецМс + НАСТРОЙКИ.доигрышМин * МИНУТА) {
    return { ок: false, почему: 'Турнир закончился: эта партия уже не засчитывается.' };
  }
  const д = данные || {};
  const исходы = ['а', 'б', 'ничья'];
  if (typeof д.партия !== 'string' || д.партия === '' || !этоНомерИгрока(д.а) || !этоНомерИгрока(д.б) ||
      д.а === д.б || исходы.indexOf(д.исход) === -1) {
    return { ок: false, почему: 'Итог партии непонятен.' };
  }
  if (Number.isFinite(д.началоМс) && д.началоМс >= турнир.конецМс) {
    return { ок: false, почему: 'Партия началась после конца турнира и не засчитывается.' };
  }
  if (турнир.пары.some(function (з) { return з.партия === д.партия; })) return { ок: true, уже: true };

  /* Кто из сторон личина: по помощнику сервера; запасной путь — флаг личинаЛи
     и ровно одна сторона, которой нет среди участников. */
  let личины = [д.а, д.б].filter(function (н) { return этоЛичина(н); });
  if (д.личинаЛи === true && личины.length === 0) {
    личины = [д.а, д.б].filter(function (н) { return !турнир.участники[String(н)]; });
    if (личины.length !== 1) return { ок: false, почему: 'Непонятно, какая из сторон личина.' };
  }
  if (личины.length === 2) return { ок: false, почему: 'В партии двух личин очков нет.' };

  const именаСторон = { а: д.имяА, б: д.имяБ };
  for (const сторона of ['а', 'б']) {
    const номер = д[сторона];
    if (личины.indexOf(номер) !== -1) continue;
    if (!турнир.участники[String(номер)]) {
      турнир.участники[String(номер)] = { имя: чистоеИмя(именаСторон[сторона]), записанМс: мс };
    }
  }
  турнир.пары.push({ партия: д.партия, а: д.а, б: д.б, исход: д.исход, личины: личины, мс: мс });
  записатьСрочно();
  освободитьПослеПартии(ид, д, личины);
  return { ок: true };
}

/** Партия принята: оба человека свободны, и теперь они «последние соперники» друг друга. */
function освободитьПослеПартии(ид, д, личины) {
  const ож = ожидания.get(ид);
  if (!ож) return;
  for (const номер of [д.а, д.б]) {
    if (личины.indexOf(номер) === -1) ож.занятые.delete(номер);
  }
  if (личины.length === 0) {
    ож.последний.set(д.а, д.б);
    ож.последний.set(д.б, д.а);
  }
}

/** Строки таблицы С НОМЕРАМИ (внутри модуля). Личины сюда не попадают. */
function строкиСНомерами(турнир) {
  const строки = new Map();
  for (const з of турнир.пары) {
    const очки = очкиЗаИсход(з.исход);
    for (const сторона of ['а', 'б']) {
      const номер = з[сторона];
      if (з.личины.indexOf(номер) !== -1) continue;
      let с = строки.get(номер);
      if (!с) {
        с = { номер: номер, очки: 0, побед: 0, ничьих: 0, поражений: 0, партий: 0, последнееОчкоМс: Infinity };
        строки.set(номер, с);
      }
      с.партий++;
      с.очки += очки[сторона];
      if (очки[сторона] > 0) с.последнееОчкоМс = з.мс;   // «раньше набрал» — по последнему приросту
      if (з.исход === 'ничья') с.ничьих++;
      else if (з.исход === сторона) с.побед++;
      else с.поражений++;
    }
  }
  return Array.from(строки.values()).sort(function (x, y) {
    return y.очки - x.очки || y.побед - x.побед || x.партий - y.партий ||
      x.последнееОчкоМс - y.последнееОчкоМс || x.номер - y.номер;
  });
}

function именоУчастника(турнир, номер) {
  const у = турнир.участники[String(номер)];
  return у ? у.имя : 'Игрок';
}

/** Таблица турнира: [{ место, имя, очки, побед, ничьих, поражений, партий, я }]. Порядок: очки →
    победы → меньше партий → кто раньше набрал. Без номеров. */
function таблица(ид, номерЯ) {
  загрузить();
  const турнир = турниры.get(ид);
  if (!турнир) return [];
  return строкиСНомерами(турнир).map(function (с, i) {
    return {
      место: i + 1, имя: именоУчастника(турнир, с.номер), очки: с.очки,
      побед: с.побед, ничьих: с.ничьих, поражений: с.поражений, партий: с.партий,
      я: номерЯ !== undefined && с.номер === номерЯ    // своя строка; номера в таблице нет
    };
  });
}

/** Место человека в таблице: { место, очки, победы, партий } или null (не участник, личина,
    нет партий). Место то же, что в таблица(ид); считаем по номеру, а не по имени. */
function местоИгрока(ид, номер) {
  загрузить();
  const турнир = турниры.get(ид);
  if (!турнир) return null;
  const строки = строкиСНомерами(турнир);
  for (let i = 0; i < строки.length; i++) {
    if (строки[i].номер === номер) {
      return { место: i + 1, очки: строки[i].очки, победы: строки[i].побед, партий: строки[i].партий };
    }
  }
  return null;
}

/** Состоялся ли турнир: сыграна хоть одна партия двух людей (без личины). */
function турнирСостоялся(турнир) {
  return !!турнир && турнир.пары.some(function (з) { return з.личины.length === 0; });
}

/** Имя первого места последнего прошедшего турнира до сегодняшнего дня (по Москве).
    Идём назад от вчера не дальше 7 дней и берём ближайший день из расписания;
    если тот турнир не состоялся — победителя нет (дальше не ищем). Только имя. */
function вчерашнийПобедитель(сейчасМс) {
  for (let назад = 1; назад <= 7; назад++) {
    const окно = окноДня(сейчасМс - назад * СУТКИ);
    if (НАСТРОЙКИ.дни.indexOf(окно.деньНедели) === -1) continue;
    const турнир = турниры.get(окно.ид);
    if (!турнирСостоялся(турнир)) return undefined;
    const первый = таблица(окно.ид)[0];
    return первый ? первый.имя : undefined;
  }
  return undefined;
}

/**
 * Итог дня: { состоялся, тройка: [{ место, имя, очки }], участников, партий }.
 * Состоялся — сыграна хоть одна партия двух людей (личина человека не заменяет).
 * Нет двух людей — «не состоялся», тройки нет.
 */
function итогДня(ид) {
  загрузить();
  const турнир = турниры.get(ид);
  if (!турнир) return { состоялся: false, тройка: [], участников: 0, партий: 0 };
  const состоялся = турнирСостоялся(турнир);
  return {
    состоялся: состоялся,
    тройка: состоялся ? таблица(ид).slice(0, 3).map(function (с) {
      return { место: с.место, имя: с.имя, очки: с.очки };
    }) : [],
    участников: Object.keys(турнир.участники).length,
    партий: турнир.пары.length
  };
}

/** То, что можно показывать всем: состояние, числа и таблица из имён и очков. Номеров нет.
    номерЯ — необязательно: у его строки я: true, а записан — записан ли он. */
function видДляВсех(сейчасМс, номерЯ) {
  загрузить();
  const общее = турнирДня(сейчасМс);
  const турнир = турниры.get(общее.ид);
  const вид = {
    ид: общее.ид,
    игра: общее.игра,
    началоМс: общее.началоМс,
    конецМс: общее.конецМс,
    состояние: общее.состояние,
    записалось: турнир ? Object.keys(турнир.участники).length : 0,
    записан: !!(турнир && номерЯ !== undefined && турнир.участники[String(номерЯ)])
  };
  вид.таблица = таблица(общее.ид, номерЯ);   // пока партий нет — пустой массив
  вид.состоялся = турнирСостоялся(турнир);
  const вчера = вчерашнийПобедитель(взятьВремя(сейчасМс));
  if (вчера !== undefined) вид.вчерашнийПобедитель = вчера;   // только имя, без номеров
  return вид;
}

