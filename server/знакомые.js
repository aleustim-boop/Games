'use strict';

/* =====================================================================
   Знакомые: кто с кем уже сидел за одним столом.

   Зачем это нужно. Человек хочет видеть, с кем он играл раньше и кто
   из них сейчас в игре, — чтобы позвать за стол не по коду из четырёх
   знаков, а по знакомому имени. Списка контактов Telegram приложению
   не даёт (и правильно делает), поэтому единственный честный источник —
   наша же память: за одним столом эти двое точно были.

   Устройство держится на одном решении: ЗАПИСЬ ОДНА НА ПАРУ.
   Не «у Ани список», не «у Бори список», а одна строка на двоих —
   с двумя номерами, двумя именами и временем последней встречи.
   Отсюда взаимность получается сама собой: «Аня видит Борю» и «Боря
   видит Аню» — это буквально одна и та же строка. Односторонней связи
   тут неоткуда взяться, и её нельзя случайно завести, убрав какую-нибудь
   проверку: проверок нет вовсе, есть устройство.

   Что храним и чего не храним. Только номер игрока в Telegram, имя
   и время последней совместной партии. Ни счёта, ни побед, ни карт,
   ни кто кого сделал дураком — для списка знакомых это не нужно,
   а лишнее хранение потом придётся объяснять.

   Забываем через 60 дней и держим не больше 50 знакомых на человека:
   иначе файл растёт без конца, а список превращается в свалку имён,
   половину которых человек уже не помнит.

   Файл переживает перезапуск сервера — это важно, сервер у нас
   перезапускают часто. Пишем отложенно и через временный файл:
   перезапуск посреди записи не должен оставить обрывок, из которого
   потом ничего не прочитать.
   ===================================================================== */

const fs = require('fs');
const path = require('path');

/* Где лежит память. В отдельной папке server/данные, и это не прихоть:
   там лежат чужие имена и номера, поэтому папка закрыта от git своим
   собственным .gitignore. Случайный коммит не утащит их в общий доступ. */
const ПАПКА = path.join(__dirname, 'данные');
const ФАЙЛ = path.join(ПАПКА, 'знакомые.json');
const ФАЙЛ_ПОКА_ПИШЕМ = ФАЙЛ + '.пишем';

/* Сколько помним знакомство. Месяца мало: сыграли на каникулах — и через
   месяц друг пропал из списка, хотя это тот же друг. Полгода — уже
   хранение ради хранения. Два месяца — срок, за который «мы играли»
   ещё правда. */
const ПОМНИМ_ДНЕЙ = 60;
const ПОМНИМ = ПОМНИМ_ДНЕЙ * 24 * 60 * 60 * 1000;

/* Потолок на человека. Больше полусотни имён в списке — это уже не список
   знакомых, а свалка: человек не узнаёт половину. Лишние вытесняются
   самыми давними. */
const ЗНАКОМЫХ_НА_ЧЕЛОВЕКА = 50;

/* Записываем не сразу: за одну партию знакомство трогают несколько раз,
   и бить по диску на каждый чих незачем. */
const ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ = 5000;

/* Потолок на весь файл — страховка от бесконечного роста на людном
   сервере. Переполнились — выбрасываем самые давние знакомства. */
const ВСЕГО_ЗАПИСЕЙ = 20000;

/* Ключ пары → { первый, второй, имяПервого, имяВторого, когда }.
   Ключ строится из двух номеров по возрастанию, поэтому пара (7, 3)
   и пара (3, 7) — это одна и та же строка, а не две. */
const знакомства = new Map();

let естьЧтоЗаписать = false;
let таймерЗаписи = null;
let ужеЗагрузили = false;

/* На диск пишет только настоящий сервер — тот, что запущен напрямую
   (см. включитьЗапись в сервер.js). Проверки поднимают сервер у себя
   в процессе с этими же модулями, и их выдуманные знакомства в настоящий
   файл попадать не должны. */
let записьРазрешена = false;

function включитьЗапись() {
  записьРазрешена = true;
}

/** Ключ пары. Порядок номеров всегда один и тот же — в этом весь смысл. */
function ключПары(первый, второй) {
  return первый < второй ? первый + ':' + второй : второй + ':' + первый;
}

/** Похоже ли это на настоящий номер игрока в Telegram. */
function этоНомерИгрока(номер) {
  return Number.isInteger(номер) && номер > 0;
}

/** Имя в память кладём коротким и без лишних пробелов. */
function привестиИмя(имя) {
  const текст = typeof имя === 'string' ? имя.trim().replace(/\s+/g, ' ') : '';
  return текст.slice(0, 32);
}

/* ---------------------------------------------------------------------
   Чтение и запись файла
   --------------------------------------------------------------------- */

/**
 * Прочитать память с диска. Файла нет — начинаем с чистого листа, это
 * обычное дело при первом запуске. Файл испорчен (сервер выключили
 * посреди записи, кто-то правил его руками) — тоже начинаем с чистого:
 * знакомства не та ценность, ради которой стоит ронять сервер.
 */
function загрузить() {
  ужеЗагрузили = true;
  let текст = '';
  try {
    текст = fs.readFileSync(ФАЙЛ, 'utf8');
  } catch (сбой) {
    return;            // файла нет — так и должно быть при первом запуске
  }
  let прочитанное = null;
  try {
    прочитанное = JSON.parse(текст);
  } catch (сбой) {
    return;            // испорчен — молча начинаем заново
  }
  if (!прочитанное || !Array.isArray(прочитанное.знакомства)) return;

  for (const запись of прочитанное.знакомства) {
    if (!запись) continue;
    const первый = Number(запись.первый);
    const второй = Number(запись.второй);
    const когда = Number(запись.когда);
    if (!этоНомерИгрока(первый) || !этоНомерИгрока(второй)) continue;
    if (первый === второй || !Number.isFinite(когда)) continue;
    знакомства.set(ключПары(первый, второй), {
      первый: Math.min(первый, второй),
      второй: Math.max(первый, второй),
      имяПервого: привестиИмя(запись.имяПервого),
      имяВторого: привестиИмя(запись.имяВторого),
      когда: когда
    });
  }
  прибраться();
}

/** Сложить память в файл. Молча: беда с диском не повод ронять партии. */
function записатьСейчас() {
  естьЧтоЗаписать = false;
  const всё = { знакомства: Array.from(знакомства.values()) };
  try {
    // Папки может не быть — например, при первом запуске на новой машине.
    fs.mkdirSync(ПАПКА, { recursive: true });
    /* Пишем во временный файл и лишь потом переименовываем. Переименование
       мгновенно, поэтому на диске всегда лежит либо старая память целиком,
       либо новая целиком — но не обрывок. Иначе перезапуск посреди записи
       стирал бы список у всех разом. */
    fs.writeFileSync(ФАЙЛ_ПОКА_ПИШЕМ, JSON.stringify(всё), 'utf8');
    fs.renameSync(ФАЙЛ_ПОКА_ПИШЕМ, ФАЙЛ);
  } catch (сбой) {
    /* Записать не вышло — знакомства останутся только в памяти
       до следующей попытки. Рассказывать об этом наружу нечего. */
  }
}

/** Пометить, что память изменилась. Настоящая запись — чуть погодя. */
function записатьпогодя() {
  if (!записьРазрешена) return;
  естьЧтоЗаписать = true;
  if (таймерЗаписи !== null) return;
  таймерЗаписи = setTimeout(function () {
    таймерЗаписи = null;
    if (естьЧтоЗаписать) записатьСейчас();
  }, ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ);
  // Таймер не должен держать программу запущенной — как и у уборщика комнат.
  if (таймерЗаписи.unref) таймерЗаписи.unref();
}

/** Записать прямо сейчас, если было что записывать (нужно при остановке). */
function дописать() {
  if (таймерЗаписи !== null) {
    clearTimeout(таймерЗаписи);
    таймерЗаписи = null;
  }
  if (естьЧтоЗаписать) записатьСейчас();
}

/* ---------------------------------------------------------------------
   Сама память
   --------------------------------------------------------------------- */

/** Выбросить забытое: слишком давнее и лишнее сверх потолков. */
function прибраться() {
  const сейчас = Date.now();
  for (const [ключ, запись] of знакомства) {
    if (сейчас - запись.когда > ПОМНИМ) знакомства.delete(ключ);
  }

  /* Потолок на человека. Считаем, у кого сколько знакомых, и у тех, кто
     перебрал, выбрасываем самые давние знакомства. */
  const сколькоУКого = new Map();
  for (const запись of знакомства.values()) {
    сколькоУКого.set(запись.первый, (сколькоУКого.get(запись.первый) || 0) + 1);
    сколькоУКого.set(запись.второй, (сколькоУКого.get(запись.второй) || 0) + 1);
  }
  for (const [номер, сколько] of сколькоУКого) {
    if (сколько <= ЗНАКОМЫХ_НА_ЧЕЛОВЕКА) continue;
    const его = [];
    for (const [ключ, запись] of знакомства) {
      if (запись.первый === номер || запись.второй === номер) его.push([ключ, запись.когда]);
    }
    его.sort(function (а, б) { return а[1] - б[1]; });   // сначала самые давние
    const лишних = его.length - ЗНАКОМЫХ_НА_ЧЕЛОВЕКА;
    for (let счёт = 0; счёт < лишних; счёт++) знакомства.delete(его[счёт][0]);
  }

  // Общий потолок — на случай людного сервера.
  if (знакомства.size > ВСЕГО_ЗАПИСЕЙ) {
    const все = Array.from(знакомства.entries())
      .sort(function (а, б) { return а[1].когда - б[1].когда; });
    const лишних = знакомства.size - ВСЕГО_ЗАПИСЕЙ;
    for (let счёт = 0; счёт < лишних; счёт++) знакомства.delete(все[счёт][0]);
  }
}

/**
 * Запомнить, что эти люди играли за одним столом.
 * Довод — список { номер, имя } тех, кто сидел за столом. Боты и все,
 * у кого номера нет (игру открыли не в Telegram), сюда просто не попадают:
 * знакомиться не с кем.
 */
function запомнитьЗастолье(застольем) {
  if (!ужеЗагрузили) загрузить();
  const люди = [];
  for (const кто of (застольем || [])) {
    const номер = кто && Number(кто.номер);
    if (!этоНомерИгрока(номер)) continue;
    if (люди.some(function (уже) { return уже.номер === номер; })) continue;
    люди.push({ номер: номер, имя: привестиИмя(кто.имя) });
  }
  if (люди.length < 2) return 0;      // одному знакомиться не с кем

  const сейчас = Date.now();
  let записано = 0;
  for (let первый = 0; первый < люди.length; первый++) {
    for (let второй = первый + 1; второй < люди.length; второй++) {
      сохранитьПару(люди[первый], люди[второй], сейчас);
      записано++;
    }
  }
  прибраться();
  записатьпогодя();
  return записано;
}

/** Одна пара: заводим новую запись или освежаем старую. */
function сохранитьПару(один, другой, когда) {
  const ключ = ключПары(один.номер, другой.номер);
  const первыйНомер = Math.min(один.номер, другой.номер);
  const первый = один.номер === первыйНомер ? один : другой;
  const второй = один.номер === первыйНомер ? другой : один;
  const прежнее = знакомства.get(ключ);
  знакомства.set(ключ, {
    первый: первый.номер,
    второй: второй.номер,
    /* Имя освежаем, но пустым не затираем: человек мог войти без имени,
       и терять из-за этого то, как его звали раньше, незачем. */
    имяПервого: первый.имя || (прежнее ? прежнее.имяПервого : ''),
    имяВторого: второй.имя || (прежнее ? прежнее.имяВторого : ''),
    когда: когда
  });
}

/**
 * С кем этот человек играл. Отдаём номера и имена — они нужны серверу,
 * чтобы спросить у комнат, кто сейчас за столом. Наружу, игроку, номера
 * не уходят: ответ собирается отдельно (см. дверь /знакомые).
 * Сначала те, с кем играли позже всех.
 */
function знакомыеИгрока(номер) {
  if (!ужеЗагрузили) загрузить();
  if (!этоНомерИгрока(номер)) return [];
  const сейчас = Date.now();
  const список = [];
  for (const запись of знакомства.values()) {
    if (сейчас - запись.когда > ПОМНИМ) continue;
    if (запись.первый === номер) {
      список.push({ номер: запись.второй, имя: запись.имяВторого, когда: запись.когда });
    } else if (запись.второй === номер) {
      список.push({ номер: запись.первый, имя: запись.имяПервого, когда: запись.когда });
    }
  }
  список.sort(function (а, б) { return б.когда - а.когда; });
  return список;
}

/** Сколько знакомств помним сейчас — для проверок. */
function сколькоЗнакомств() {
  if (!ужеЗагрузили) загрузить();
  return знакомства.size;
}

/** Забыть всё (нужно проверкам, чтобы начинать с чистого листа). */
function забытьВсё() {
  знакомства.clear();
  ужеЗагрузили = true;
  записатьпогодя();
}

