'use strict';

/* =====================================================================
   ПРИСУТСТВИЕ: кто сейчас в приложении (не за столом, а вообще).

   Зачем это нужно. Друг видит в списке «Мои друзья», что вы сейчас
   внутри игры, и может позвать вас одним нажатием, не выходя из
   Telegram. Чтобы это работало, серверу нужно знать, кто стучался
   в дверь /друзья-онлайн совсем недавно, — этим и занимается файл.

   Что хранится в ПАМЯТИ (пропадает при перезапуске сервера, и это
   нарочно — см. штаб/план-друзья-онлайн-черновик.md, риск 8):
   номер игрока -> { имя, когда }. «Когда» — время последнего стука.
   Это история заходов, слежка на диске нам не нужна.

   Что хранится на ДИСКЕ: только список тех, кто нажал «не показывать
   меня друзьям» (server/данные/прячутся.json). Это решение человека,
   и терять его при перезапуске сервера нельзя — иначе он окажется
   снова видимым без своего согласия. Устройство файла повторяет
   server/не-звать.js: запись через временный файл и переименование,
   включитьЗапись() отделяет боевую запись от проверок.

   Приватность (штаб/план-друзья-онлайн-черновик.md, раздел 6):
   наружу отдаём ТОЛЬКО тех, о ком спросили (наСвязиИзСписка) — весь
   список присутствия перебирать и раздавать нельзя, иначе присутствие
   само станет способом следить за незнакомыми людьми. Номер Telegram
   в журнал (console.*) не печатаем нигде в этом файле.
   ===================================================================== */

const fs = require('fs');

/* Где лежат данные — то же общее место, что у всех соседей. Своей копии
   пути здесь нет: проверки уводят папку в сторону через ДАННЫЕ_ИГРЫ,
   и писать мимо неё в боевые данные нельзя (см. server/папка-данных.js). */
const гдеДанные = require('./папка-данных.js');

/** Папка с данными прямо сейчас. */
function папка() { return гдеДанные.папка(); }

/** Файл со списком прячущихся. */
function файл() { return гдеДанные.файл('прячутся.json'); }

/** Временный файл, в который пишем перед переименованием. */
function файлПокаПишем() { return файл() + '.пишем'; }

/* Сколько молчания ещё считаем «человек здесь». 90 секунд при опросе
   раз в 30 — с запасом на два пропущенных стука подряд (страница могла
   на миг свернуться или сеть моргнуть). Переменная модуля, а не
   константа: подменитьВремяЖизниДляПроверки ниже подставляет короткое
   значение, чтобы проверки не ждали полторы минуты по-настоящему. */
const ПРИСУТСТВИЕ_ЖИВЁТ_ПО_УМОЛЧАНИЮ = 90000;
let присутствиеЖивётМс = ПРИСУТСТВИЕ_ЖИВЁТ_ПО_УМОЛЧАНИЮ;

/**
 * Только для проверок (tests/присутствие.js): подменить срок жизни
 * присутствия перед следующими вызовами. Без числа (null/undefined)
 * возвращает обычные 90 секунд.
 */
function подменитьВремяЖизниДляПроверки(мс) {
  присутствиеЖивётМс = Number.isFinite(мс) ? мс : ПРИСУТСТВИЕ_ЖИВЁТ_ПО_УМОЛЧАНИЮ;
}

/* Потолок числа записей — страховка от бесконечного роста памяти.
   Для присутствия переполнились — выбрасываем самые давние (у них
   есть срок жизни, есть что выбрасывать без потери решения человека).
   Для прячущихся это не годится: запись там одна и та же — «мне не
   видно», бессрочное решение конкретного человека, и старых записей
   ради нового человека выбрасывать нельзя. Поэтому у прячущихся потолок
   работает иначе — отказом (см. прятаться): сверх потолка новую запись
   просто не добавляем, а не выселяем чужую. */
const ВСЕГО_ЗАПИСЕЙ = 20000;

/* Присутствие: номер игрока -> { имя, когда }. Только в памяти. */
const присутствие = new Map();

/* Прячущиеся: номер игрока -> когда включили скрытность. Это то, что
   переживает перезапуск сервера (пишется на диск). */
const прячущиеся = new Map();

let естьЧтоЗаписать = false;
let таймерЗаписи = null;
let ужеЗагрузили = false;

/* На диск пишет только настоящий сервер — тот, что запущен напрямую
   (см. включитьЗапись в сервер.js). Проверки поднимают сервер у себя
   в процессе с этими же модулями, и их выдуманная скрытность в
   настоящий файл попадать не должна. */
let записьРазрешена = false;

function включитьЗапись() {
  записьРазрешена = true;
}

/** Похоже ли это на настоящий номер игрока в Telegram (уже числом). */
function этоНомерИгрока(номер) {
  return Number.isInteger(номер) && номер > 0;
}

/**
 * Привести сырой вход к номеру игрока: подходят только число или строка
 * из одних цифр. Всё прочее — null: логическое, объект, массив, дробное,
 * отрицательное, число с буквами. Отдельно от этоНомерИгрока и всегда
 * перед ним: Number(true) === 1, и без этой проверки отметить(true, …)
 * или прятаться(true, …) тихо приняли бы «да/нет» за игрока номер 1.
 */
function привестиНомерИгрока(сырое) {
  if (typeof сырое === 'number') {
    return этоНомерИгрока(сырое) ? сырое : null;
  }
  if (typeof сырое === 'string') {
    const текст = сырое.trim();
    if (!/^[0-9]+$/.test(текст)) return null;   // только цифры, без знаков и точек
    const число = Number(текст);
    return этоНомерИгрока(число) ? число : null;
  }
  return null;   // boolean, null, undefined, объект — не номер
}

/* Ждём перед записью на диск: переключатель «меня видно» не жмут
   пачками, но бить по диску на каждое нажатие незачем. 5 секунд —
   как в server/не-звать.js. */
const ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ = 5000;

/** Имя в память кладём коротким и без лишних пробелов — как у соседей
    (server/знакомые.js): длинное или мусорное имя из Telegram не должно
    раздувать память присутствия. */
function привестиИмя(имя) {
  const текст = typeof имя === 'string' ? имя.trim().replace(/\s+/g, ' ') : '';
  return текст.slice(0, 32);
}

/* ---------------------------------------------------------------------
   Чтение и запись файла прячущихся
   --------------------------------------------------------------------- */

/**
 * Прочитать список прячущихся с диска. Файла нет — обычное дело при
 * первом запуске. Файл испорчен — начинаем с чистого листа: ронять
 * сервер из-за этого нельзя, а решение спрятаться человек повторит
 * одним нажатием переключателя.
 */
function загрузить() {
  ужеЗагрузили = true;
  let текст = '';
  try {
    текст = fs.readFileSync(файл(), 'utf8');
  } catch (сбой) {
    return;            // файла нет — так и должно быть при первом запуске
  }
  let прочитанное = null;
  try {
    прочитанное = JSON.parse(текст);
  } catch (сбой) {
    return;            // испорчен — молча начинаем заново
  }
  if (!прочитанное || !Array.isArray(прочитанное.прячутся)) return;

  for (const запись of прочитанное.прячутся) {
    if (!запись) continue;
    const номер = Number(запись.номер);
    const когда = Number(запись.когда);
    if (!этоНомерИгрока(номер) || !Number.isFinite(когда)) continue;
    прячущиеся.set(номер, когда);
  }
}

/** Сложить список прячущихся в файл. Молча: беда с диском не повод ронять партии. */
function записатьСейчас() {
  естьЧтоЗаписать = false;
  const всё = { прячутся: [] };
  for (const [номер, когда] of прячущиеся) {
    всё.прячутся.push({ номер: номер, когда: когда });
  }
  try {
    // Папки может не быть — например, при первом запуске на новой машине.
    fs.mkdirSync(папка(), { recursive: true });
    /* Пишем во временный файл и лишь потом переименовываем: на диске
       всегда лежит либо старый список целиком, либо новый целиком —
       но не обрывок. */
    fs.writeFileSync(файлПокаПишем(), JSON.stringify(всё), 'utf8');
    fs.renameSync(файлПокаПишем(), файл());
  } catch (сбой) {
    /* Записать не вышло — список останется в памяти до следующей
       попытки. Рассказывать об этом наружу нечего. */
  }
}

/** Пометить, что список изменился. Настоящая запись — чуть погодя. */
function записатьпогодя() {
  if (!записьРазрешена) return;
  естьЧтоЗаписать = true;
  if (таймерЗаписи !== null) return;
  таймерЗаписи = setTimeout(function () {
    таймерЗаписи = null;
    if (естьЧтоЗаписать) записатьСейчас();
  }, ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ);
  // Таймер не должен держать программу запущенной — как и у соседей.
  if (таймерЗаписи.unref) таймерЗаписи.unref();
}

/**
 * Записать НЕМЕДЛЕННО, без пятисекундного ожидания. Зовём только когда
 * человек включает скрытность («меня не видно») — это его решение,
 * и упади сервер в те пять секунд, что запись ждала диска, друзья на
 * миг увидят его снова видимым вопреки выбору (см. server/не-звать.js,
 * тот же приём для отказа 'сам'). Снятие скрытности от такой беды не
 * страдает — оно лишь возвращает прежнюю, более открытую видимость,
 * поэтому идёт обычной отложенной записью (записатьпогодя).
 */
function записатьСрочно() {
  if (!записьРазрешена) return;
  if (таймерЗаписи !== null) {
    clearTimeout(таймерЗаписи);
    таймерЗаписи = null;
  }
  записатьСейчас();
}

/** Записать прямо сейчас, если было что записывать (нужно проверкам и при остановке). */
function дописать() {
  if (таймерЗаписи !== null) {
    clearTimeout(таймерЗаписи);
    таймерЗаписи = null;
  }
  if (естьЧтоЗаписать) записатьСейчас();
}

/* ---------------------------------------------------------------------
   Уборка по потолку записей
   --------------------------------------------------------------------- */

/** Выбросить из карты самые давние записи сверх потолка. */
function обрезатьПоПотолку(карта, времяЗаписи) {
  if (карта.size <= ВСЕГО_ЗАПИСЕЙ) return;
  const порядок = Array.from(карта.entries()).sort(function (а, б) {
    return времяЗаписи(а[1]) - времяЗаписи(б[1]);   // самые давние — первыми
  });
  const лишних = карта.size - ВСЕГО_ЗАПИСЕЙ;
  for (let счёт = 0; счёт < лишних; счёт++) карта.delete(порядок[счёт][0]);
}

/* Полный перебор присутствия (поиск протухших записей) — это O(n), и
   гонять его на каждый стук (см. отметить) незачем: наСвязиИзСписка
   ниже сама проверяет свежесть каждой запрошенной записи при чтении,
   так что чуть более долгоживущая протухшая запись в общей карте
   ничего не портит для тех, кто спрашивает. Поэтому дорогой перебор
   запускаем не чаще раза в 5 секунд — этого хватает, чтобы карта не
   пухла между обращениями, а не чаще двух прочитанных строк. */
const УБОРКА_ПРИСУТСТВИЯ_НЕ_ЧАЩЕ_МС = 5000;
let последняяУборкаПрисутствия = 0;

/** Выбросить протухшее присутствие (не чаще раза в 5 сек) и лишнее сверх потолка (всегда). */
function прибратьсяПрисутствие() {
  const сейчас = Date.now();
  if (сейчас - последняяУборкаПрисутствия >= УБОРКА_ПРИСУТСТВИЯ_НЕ_ЧАЩЕ_МС) {
    последняяУборкаПрисутствия = сейчас;
    for (const [номер, запись] of присутствие) {
      if (сейчас - запись.когда > присутствиеЖивётМс) присутствие.delete(номер);
    }
  }
  /* Потолок проверяем всегда: сама проверка размера — O(1), а дорогая
     сортировка внутри срабатывает лишь при настоящем переполнении. */
  обрезатьПоПотолку(присутствие, function (запись) { return запись.когда; });
}

/* ---------------------------------------------------------------------
   Присутствие
   --------------------------------------------------------------------- */

/**
 * Человек постучался — записать, что он здесь. Сам факт вызова этой
 * функции и есть «я в приложении»: отдельного «выхода» не бывает,
 * присутствие просто протухает по времени (см. присутствиеЖивётМс).
 */
function отметить(номер, имя) {
  const кого = привестиНомерИгрока(номер);
  if (кого === null) return false;
  присутствие.set(кого, { имя: привестиИмя(имя), когда: Date.now() });
  прибратьсяПрисутствие();
  return true;
}

/**
 * Кто из ЭТИХ номеров сейчас на связи. Отвечает только про тех, о ком
 * спросили, — тот же приём, что у ктоСейчасЗаСтолом в server/комнаты.js:
 * перебирать всю карту присутствия и отдавать её наружу целиком нельзя,
 * иначе присутствие само станет слежкой за незнакомыми людьми.
 * Прячущихся в ответе нет вовсе — для спросившего они «не на связи».
 */
function наСвязиИзСписка(номера) {
  if (!ужеЗагрузили) загрузить();
  const результат = new Map();
  // Не массив — не перебираем: for..of на объекте/строке тихо повёл бы
  // себя не так, как ждёт вызывающий код, а спросили явно про список.
  if (!Array.isArray(номера)) return результат;
  const сейчас = Date.now();
  for (const исходный of номера) {
    const кого = привестиНомерИгрока(исходный);
    if (кого === null) continue;
    if (прячущиеся.has(кого)) continue;
    const запись = присутствие.get(кого);
    if (!запись) continue;
    if (сейчас - запись.когда > присутствиеЖивётМс) continue;
    результат.set(кого, { когда: запись.когда, имя: запись.имя });
  }
  return результат;
}

/**
 * Сколько человек прямо сейчас числятся на связи (для проверок и
 * статистики). Считаем точно и без троттлинга: эту функцию, в отличие
 * от отметить(), не дёргают на каждый пользовательский стук, а карту
 * при этом не трогаем — протухшие записи почистит своим чередом
 * прибратьсяПрисутствие() из ближайшего отметить().
 */
function сколькоНаСвязи() {
  const сейчас = Date.now();
  let счёт = 0;
  for (const запись of присутствие.values()) {
    if (сейчас - запись.когда <= присутствиеЖивётМс) счёт++;
  }
  return счёт;
}

/* ---------------------------------------------------------------------
   Скрытность («меня не видно»)
   --------------------------------------------------------------------- */

/**
 * Спрятаться (да = true) или снова стать видимым (да = false).
 * Потолок у прячущихся — это отказ, а не выселение: если человека ещё
 * нет в списке и список уже полон, возвращаем false и ничего не пишем,
 * а не выбрасываем чужое бессрочное решение ради нового.
 */
function прятаться(номер, да) {
  if (!ужеЗагрузили) загрузить();
  const кого = привестиНомерИгрока(номер);
  if (кого === null) return false;
  if (да) {
    if (!прячущиеся.has(кого) && прячущиеся.size >= ВСЕГО_ЗАПИСЕЙ) return false;
    прячущиеся.set(кого, Date.now());
    записатьСрочно();
  } else {
    прячущиеся.delete(кого);
    записатьпогодя();
  }
  return true;
}

/** Прячется ли этот номер прямо сейчас. */
function прячетсяЛи(номер) {
  if (!ужеЗагрузили) загрузить();
  const кого = привестиНомерИгрока(номер);
  if (кого === null) return false;
  return прячущиеся.has(кого);
}

/** Забыть всё (нужно проверкам, чтобы начинать с чистого листа). */
function забытьВсё() {
  присутствие.clear();
  прячущиеся.clear();
  ужеЗагрузили = true;
  записатьпогодя();
}

