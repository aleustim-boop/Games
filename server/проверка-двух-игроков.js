/* Больше этого числа действий одна партия занять не может —
   значит, где-то заело. */
const ПРЕДЕЛ_ДЕЙСТВИЙ = 500;

let пройдено = 0;
const провалы = [];

function проверить(условие, что) {
  if (условие) {
    пройдено++;
    return true;
  }
  провалы.push(что);
  console.log('  ПРОВАЛ: ' + что);
  return false;
}

/* ---------------------------------------------------------------------
   Сыщик: ищет чужие карты в том, что уходит клиенту
   --------------------------------------------------------------------- */

function ключКарты(карта) {
  return карта.масть + карта.имя;
}

/** Собрать все карты, встречающиеся в ответе, на любой глубине. */
function картыИзОтвета(что, найденные) {
  const список = найденные || [];
  if (!что || typeof что !== 'object') return список;

  if (Array.isArray(что)) {
    for (const кусок of что) картыИзОтвета(кусок, список);
    return список;
  }
  if (typeof что.масть === 'string' && typeof что.имя === 'string') список.push(что);
  for (const ключ of Object.keys(что)) картыИзОтвета(что[ключ], список);
  return список;
}

/**
 * Карты, которых игрок видеть не должен: рука соперника, вся колода
 * и отбой. Открытая козырная карта под колодой — исключение: она лежит
 * лицом вверх и в жизни, и в игре против робота. Но как только колода
 * разобрана, эта карта у кого-то в руке, и тогда она тоже под запретом.
 */
function запрещённыеКарты(партия, ктоЯ) {
  const запрет = new Map();
  const колодаЦела = партия.колода.length > 0;
  const открытая = колодаЦела ? ключКарты(партия.козырнаяКарта) : null;

  const добавить = function (карта, откуда) {
    const ключ = ключКарты(карта);
    if (ключ === открытая) return;   // её видеть можно
    запрет.set(ключ, откуда);
  };

  for (const карта of партия.руки[партии.соперник(ктоЯ)]) добавить(карта, 'рука соперника');
  for (const карта of партия.колода) добавить(карта, 'колода');
  for (const карта of партия.отбой) добавить(карта, 'отбой');
  return запрет;
}

/**
 * Найти в готовом ответе все карты, которых игроку видеть нельзя.
 * Ищем двумя способами сразу: разбираем ответ по косточкам и,
 * отдельно, ищем карту прямо в тексте — в том самом, что уйдёт
 * в браузер. Второй способ ловит карту, спрятанную в строке.
 */
function найтиЧужие(вид, запрет) {
  const беды = [];
  for (const карта of картыИзОтвета(вид)) {
    const ключ = ключКарты(карта);
    if (запрет.has(ключ)) беды.push('в ответе есть чужая карта ' + ключ + ' (' + запрет.get(ключ) + ')');
  }

  const текст = JSON.stringify(вид);
  for (const [ключ, откуда] of запрет) {
    const кусок = '"масть":"' + ключ[0] + '","имя":"' + ключ.slice(1) + '"';
    if (текст.indexOf(кусок) !== -1) {
      беды.push('в тексте ответа видна чужая карта ' + ключ + ' (' + откуда + ')');
    }
  }
  return беды;
}

let сыщикРаботает = false;
let осмотрено = 0;
const настоящийВид = партии.видДляИгрока;

/** Подменить единственную дверь наружу на сыщика. */
function поставитьСыщика() {
  if (сыщикРаботает) return;
  сыщикРаботает = true;

  партии.видДляИгрока = function (партия, ктоЯ, добавка) {
    const вид = настоящийВид(партия, ктоЯ, добавка);
    if (!партия) return вид;

    осмотрено++;
    const запрет = запрещённыеКарты(партия, ктоЯ);
    for (const беда of найтиЧужие(вид, запрет)) проверить(false, беда);

    // И заодно: колода и роли игроков наружу уходить не должны вовсе.
    const текст = JSON.stringify(вид);
    if (текст.indexOf('"колода"') !== -1) проверить(false, 'в ответе оказалась колода целиком');
    if (текст.indexOf('"руки"') !== -1) проверить(false, 'в ответе оказались руки обоих игроков');
    if (партия.колода.length === 0 && вид.козырнаяКарта !== null) {
      проверить(false, 'козырная карта показана после того, как её забрали из колоды');
    }
    return вид;
  };
}

function убратьСыщика() {
  партии.видДляИгрока = настоящийВид;
  сыщикРаботает = false;
}

/* ---------------------------------------------------------------------
   Поддельный игрок
   --------------------------------------------------------------------- */

function создатьИгрока(имя) {
  return {
    имя: имя,
    код: null,
    пропуск: null,
    версия: 0,
    вид: null,
    отказы: [],

    /** Любой запрос к серверу. Заодно сверяем, что в ответе нет лишнего. */
    async запрос(путь, тело) {
      const ответ = await fetch(АДРЕС + путь, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(тело || {})
      });
      const текст = await ответ.text();
      // Проверяем сырой ответ: внутренние имена правил наружу не ходят.
      if (текст.indexOf('"человек"') !== -1 || текст.indexOf('"бот"') !== -1) {
        проверить(false, 'в ответе сервера видны внутренние имена игроков');
      }
      return { код: ответ.status, тело: текст ? JSON.parse(текст) : null };
    },

    запомнить(состояние) {
      if (!состояние) return;
      this.вид = состояние;
      this.версия = состояние.версия;
    },

    async создатьКомнату() {
      const ответ = await this.запрос('/создать');
      this.код = ответ.тело.код;
      this.пропуск = ответ.тело.пропуск;
      this.запомнить(ответ.тело.состояние);
      return ответ;
    },

    async войти(код) {
      const ответ = await this.запрос('/войти', { код: код });
      if (ответ.тело && ответ.тело.пропуск) {
        this.код = ответ.тело.код;
        this.пропуск = ответ.тело.пропуск;
        this.запомнить(ответ.тело.состояние);
      }
      return ответ;
    },

    async обновить() {
      const ответ = await this.запрос('/состояние', { код: this.код, пропуск: this.пропуск });
      if (ответ.тело && ответ.тело.состояние) this.запомнить(ответ.тело.состояние);
      return ответ;
    },

    async сходить(намерение) {
      const посылка = Object.assign({ код: this.код, пропуск: this.пропуск }, намерение);
      const ответ = await this.запрос('/ход', посылка);
      if (ответ.тело && ответ.тело.состояние) this.запомнить(ответ.тело.состояние);
      if (ответ.тело && ответ.тело.принято === false) this.отказы.push(ответ.тело.причина);
      return ответ;
    },

    async чтоНового() {
      const ответ = await this.запрос('/что-нового', {
        код: this.код, пропуск: this.пропуск, версия: this.версия
      });
      if (ответ.тело && ответ.тело.состояние) this.запомнить(ответ.тело.состояние);
      return ответ;
    },

    async уйти() {
      return this.запрос('/выйти', { код: this.код, пропуск: this.пропуск });
    }
  };
}

/* ---------------------------------------------------------------------
   Как поддельный игрок выбирает ход
   --------------------------------------------------------------------- */

/**
 * Решение принимается только по своему виду — тому же, что видит браузер.
 * Правило «чем бьётся карта» берём из общего файла игры: у стола карты
 * открыты, так что подглядывания здесь нет.
 */
function придуматьХод(вид) {
  if (!вид.яХожу || вид.завершена) return null;

  if (вид.фаза === 'защита') {
    for (let п = 0; п < вид.стол.length; п++) {
      if (вид.стол[п].защита) continue;
      for (let к = 0; к < вид.мояРука.length; к++) {
        if (правила.бьёт(вид.мояРука[к], вид.стол[п].атака, вид.козырь)) {
          return { действие: 'отбить', пара: п, карта: к };
        }
      }
      return { действие: 'беру' };   // эту карту крыть нечем
    }
    return { действие: 'беру' };
  }

  if (вид.фаза === 'атака') return { действие: 'ходить', карта: 0 };

  // Подкидывание и докидывание: ищем карту того же достоинства, что на столе.
  const достоинства = правила.достоинстваНаСтоле({ стол: вид.стол });
  for (let к = 0; к < вид.мояРука.length; к++) {
    if (достоинства.indexOf(вид.мояРука[к].имя) !== -1) {
      return { действие: 'ходить', карта: к };
    }
  }
  return { действие: 'бито' };
}

/** Запасной ход, если сервер отказал: закончить подход или взять. */
function запаснойХод(вид) {
  if (вид.фаза === 'защита') return { действие: 'беру' };
  return { действие: 'бито' };
}

/**
 * Один игрок играет, пока партия не кончится. Не его очередь —
 * висит на длинном опросе и ждёт новостей.
 */
async function игратьДоКонца(игрок) {
  let действий = 0;

  while (игрок.вид && !игрок.вид.завершена && действий < ПРЕДЕЛ_ДЕЙСТВИЙ) {
    действий++;

    if (!игрок.вид.яХожу) {
      const ответ = await игрок.чтоНового();
      if (ответ.тело && ответ.тело.комнатыНет) return действий;
      continue;
    }

    const намерение = придуматьХод(игрок.вид);
    if (!намерение) continue;

    const ответ = await игрок.сходить(намерение);
    if (ответ.тело && ответ.тело.принято === false) {
      // Подкинуть не дали (стол полон или у соперника мало карт) —
      // это законный отказ, просто заканчиваем подход.
      const запас = запаснойХод(игрок.вид);
      const второй = await игрок.сходить(запас);
      проверить(второй.тело.принято === true,
        'запасной ход тоже отклонён: ' + (второй.тело && второй.тело.причина));
    }
  }

  проверить(действий < ПРЕДЕЛ_ДЕЙСТВИЙ, 'партия не закончилась за ' + ПРЕДЕЛ_ДЕЙСТВИЙ + ' действий');
  return действий;
}

/** Свести двоих в новой комнате и вернуть обоих игроков. */
async function собратьПартию() {
  const первый = создатьИгрока('первый');
  const второй = создатьИгрока('второй');
  await первый.создатьКомнату();
  await второй.войти(первый.код);
  await первый.обновить();
  return { первый: первый, второй: второй };
}

