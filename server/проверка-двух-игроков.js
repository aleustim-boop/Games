/* =====================================================================
   Проверка сервера без второго живого человека.

   Запуск:
       node server/проверка-двух-игроков.js          (20 партий)
       node server/проверка-двух-игроков.js 200      (сколько скажете)

   Здесь поднимается настоящий сервер и к нему подключаются два
   поддельных игрока. Каждый ходит по обычному HTTP и видит ровно то же,
   что увидел бы браузер: свои карты, стол и числа. Чужих карт
   поддельный игрок не знает и знать не может — как и живой.

   Что проверяется:
     1) партия проходит от раздачи до конца и кто-то остаётся дураком;
     2) длинный опрос будит второго игрока после хода первого;
     3) неверные ходы отклоняются, и причина написана словами;
     4) код комнаты перестаёт работать, как только вошли двое;
     5) игрок пропал и вернулся — партия на месте, карты те же;
     6) брошенная комната убирается, память не растёт;
     7) ЧУЖИЕ КАРТЫ НЕ УТЕКАЮТ — проверяется на каждом ответе сервера.

   Про седьмой пункт отдельно. Все данные выходят наружу через одну
   функцию — видДляИгрока. На время проверки она подменяется сыщиком:
   тот берёт настоящее состояние партии, составляет список карт,
   которые игроку видеть НЕ положено (рука соперника, колода, отбой),
   и ищет их в том, что уходит клиенту, — и по объектам, и по тексту
   ответа. Нашлась хоть одна — проверка провалена.
   ===================================================================== */

