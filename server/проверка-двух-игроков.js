/** Козыри должны лежать в конце руки — у обоих игроков одинаково. */
function рукаРазложена(рука, козырь) {
  let встретилсяКозырь = false;
  for (const карта of рука) {
    if (карта.масть === козырь) встретилсяКозырь = true;
    else if (встретилсяКозырь) return false;   // некозырь после козыря — не разложено
  }
  return true;
}

async function сценарийТекстовОтказа() {
  console.log('6. Отказы объясняются понятными словами');
  const { первый, второй } = await собратьПартию();

  проверить(рукаРазложена(первый.вид.мояРука, первый.вид.козырь),
    'у первого игрока козыри лежат в конце руки');
  проверить(рукаРазложена(второй.вид.мояРука, второй.вид.козырь),
    'у второго игрока рука разложена так же, а не вперемешку');

  // Доводим стол до состояния «всё отбито» — тогда можно подкидывать.
  const ходит = первый.вид.яХожу ? первый : второй;
  const кроет = первый.вид.яХожу ? второй : первый;

  await ходит.сходить({ действие: 'ходить', карта: 0 });
  await кроет.обновить();
  const чем = придуматьХод(кроет.вид);
  if (чем && чем.действие === 'отбить') {
    await кроет.сходить(чем);
    await ходит.обновить();

    if (ходит.вид.фаза === 'подкидывание') {
      const наСтоле = правила.достоинстваНаСтоле({ стол: ходит.вид.стол });
      let чужая = -1;
      for (let к = 0; к < ходит.вид.мояРука.length; к++) {
        if (наСтоле.indexOf(ходит.вид.мояРука[к].имя) === -1) { чужая = к; break; }
      }
      if (чужая !== -1) {
        const отказ = await ходит.сходить({ действие: 'ходить', карта: чужая });
        проверить(отказ.тело.принято === false, 'подкинуть чужим достоинством нельзя');
        проверить(/^Подкинуть можно только /.test(отказ.тело.причина || ''),
          'причина называет, чем можно подкинуть: ' + отказ.тело.причина);
      }
    }
  }
  await первый.уйти();
  await второй.уйти();

  /* Два оставшихся отказа по сети подстроить трудно — там нужен полный
     стол. Спрашиваем правила напрямую, разложив карты руками. */
  const партия = партии.начатьПартию();
  const атакует = партия.атакует;
  const защитник = партии.соперник(атакует);

  // Стол забит шестью парами: больше в подход не кладут.
  партия.стол = [];
  for (let п = 0; п < 6; п++) {
    партия.стол.push({ атака: партия.колода[п * 2], защита: партия.колода[п * 2 + 1] });
  }
  const полный = партии.сделатьХод(партия, атакует, { действие: 'ходить', карта: 0 });
  проверить(/шесть карт/.test(полный.причина || ''),
    'при полном столе так и сказано: ' + полный.причина);

  // У защитника одна карта, а на столе неотбитая — докидывать некуда.
  партия.стол = [{ атака: партия.колода[0], защита: null }];
  партия.руки[защитник] = [партия.колода[1]];
  партия.берёт = true;   // защитник уже сказал «Беру», ход снова у атакующего
  const мало = партии.сделатьХод(партия, атакует, { действие: 'ходить', карта: 0 });
  проверить(/меньше карт/.test(мало.причина || ''),
    'про нехватку карт у соперника сказано понятно: ' + мало.причина);
}

async function сценарийРеванша() {
  console.log('7. Реванш: несколько партий подряд в одной комнате');
  const { первый, второй } = await собратьПартию();
  const кодКомнаты = первый.код;
  const пропускПервого = первый.пропуск;

  for (let н = 1; н <= 3; н++) {
    await Promise.all([игратьДоКонца(первый), игратьДоКонца(второй)]);
    проверить(первый.вид.завершена === true, 'партия ' + н + ' в комнате доиграна');
    if (н === 3) break;

    // Один зовёт, второй пока не ответил.
    const зов = await первый.сходить({ действие: 'ещё' });
    проверить(зов.тело.принято === true, 'предложение сыграть ещё принято');
    await второй.чтоНового();
    проверить(второй.вид.соперникХочетЕщё === true, 'соперник видит предложение сыграть ещё');
    проверить(второй.вид.этап === 'конец', 'пока второй не согласился, новой раздачи нет');

    // Второй соглашается — карты раздаются заново.
    const итогБыл = первый.вид.итог;                  // после раздачи он обнулится
    const дуракБыл = итогБыл === 'поражение' ? 'первый' : 'второй';
    const согласие = await второй.сходить({ действие: 'ещё' });
    проверить(согласие.тело.принято === true, 'согласие на реванш принято');
    await первый.чтоНового();

    проверить(первый.код === кодКомнаты && первый.пропуск === пропускПервого,
      'код комнаты и пропуск не поменялись');
    проверить(первый.вид.этап === 'игра', 'после согласия началась новая партия');
    проверить(первый.вид.мояРука.length === 6 && второй.вид.мояРука.length === 6,
      'обоим раздали по шесть карт заново');
    проверить(первый.вид.вКолоде === 24, 'колода снова полная');
    проверить(первый.вид.сыграноПартий === н, 'сервер помнит, сколько партий сыграно: ' + первый.вид.сыграноПартий);
    проверить(первый.вид.яХочуЕщё === false && первый.вид.соперникХочетЕщё === false,
      'после раздачи метки «хочу ещё» сброшены');

    // Проигравший ходит первым — так принято в «Дураке».
    // При ничьей никого не назначаем, там решает младший козырь.
    if (итогБыл !== 'ничья') {
      const первымХодитПервый = первый.вид.яАтакую;
      проверить((дуракБыл === 'первый') === первымХодитПервый,
        'первым ходит проигравший прошлую партию');
    }
  }

  // Отказ от реванша — это обычный выход, и соперник его видит.
  await первый.сходить({ действие: 'ещё' });
  await второй.уйти();
  await первый.чтоНового();
  проверить(первый.вид.соперникУшёл === true, 'отказ от реванша виден как уход соперника');
  const впустую = await первый.сходить({ действие: 'ещё' });
  проверить(впустую.тело.принято === false, 'звать ушедшего играть дальше нельзя');
  проверить(/вышел/.test(впустую.тело.причина || ''), 'причина отказа понятна: ' + впустую.тело.причина);

  await первый.уйти();
}

/** Простой запрос к серверу от имени страницы с указанным адресом. */
async function запросОтСтраницы(путь, адресСтраницы) {
  const заголовки = { 'Content-Type': 'application/json' };
  if (адресСтраницы) заголовки.Origin = адресСтраницы;
  const ответ = await fetch(АДРЕС + путь, { method: 'POST', headers: заголовки, body: '{}' });
  return {
    код: ответ.status,
    разрешение: ответ.headers.get('access-control-allow-origin'),
    тело: await ответ.json().catch(function () { return null; })
  };
}

