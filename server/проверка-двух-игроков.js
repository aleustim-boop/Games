async function многоПартий(сколько) {
  console.log('10. Подряд партий: ' + сколько);
  const началось = Date.now();
  let ничьих = 0;
  let всегоДействий = 0;

  for (let н = 1; н <= сколько; н++) {
    const { первый, второй } = await собратьПартию();
    const шаги = await Promise.all([игратьДоКонца(первый), игратьДоКонца(второй)]);
    всегоДействий += шаги[0] + шаги[1];

    if (!первый.вид.завершена || !второй.вид.завершена) {
      проверить(false, 'партия номер ' + н + ' не дошла до конца');
      break;
    }
    if (первый.вид.итог === 'ничья') ничьих++;

    await первый.уйти();
    await второй.уйти();
  }

  const секунд = ((Date.now() - началось) / 1000).toFixed(1);
  console.log('   сыграно ' + сколько + ' партий за ' + секунд + ' с, ничьих ' + ничьих +
    ', всего действий ' + всегоДействий);
  проверить(комнаты.сколькоКомнат() === 0, 'после ухода обоих комнаты не остаются висеть');
}

