'use strict';

/* =====================================================================
   Партия по сети: тонкая прослойка между правилами и сетью.

   Здесь НЕТ ни одного правила игры — все они берутся из js/game.js
   обычным require. Если правило понадобится новое, его добавляют там,
   а не здесь: иначе однажды сервер и игра в браузере разойдутся,
   и найти это будет очень трудно.

   Задачи файла ровно четыре:
     1) раздать партию на нужное число мест (от двух до шести)
        и в нужной разновидности — обычной, переводной, парами;
     2) собрать «вид для игрока» — то, что можно показать именно ему
        (свои карты видит, чужие не видит вообще);
     3) выполнить намерение игрока («хочу сходить этой картой») —
        проверить его правилами и объяснить отказ человеческими словами;
     4) сходить за бота — тем же ботом, что и в игре без сети.

   Почему ход бота живёт здесь, а не в браузере. Если бы за бота ходил
   чей-то телефон, все остальные увидели бы этот ход с опозданием,
   а при обрыве связи у «ведущего» игра встала бы совсем. Поэтому боты
   ходят на сервере: он один, и картина у всех получается одна.

   Про безопасность: вид для игрока — единственная дверь, через которую
   данные партии выходят наружу. Ни сервер, ни комнаты не имеют права
   отдавать объект партии клиенту напрямую. Тогда проверять утечку чужих
   карт нужно в одном месте, а не по всему коду.
   ===================================================================== */

const правила = require('../js/game.js');

/* Имена мест за столом спрашиваем у самих правил, а не переписываем сюда
   вторым списком: копия однажды разойдётся с игрой, и разбираться придётся
   долго. Спросить проще всего так — раздать одну пробную партию на полный
   стол и посмотреть, как правила назвали места. Делается один раз при
   запуске сервера, карты этой партии тут же выбрасываются.

   Первые два имени — те же, что были всегда ('человек' и 'бот'): на них
   держится игра вдвоём, поэтому порядок мест менять нельзя. */
const МЕСТА = правила.создатьПартию({ игроков: правила.МАКС_ИГРОКОВ }).игроки.slice();

/* Создатель комнаты садится на первое место, второй пришедший — на второе.
   Наружу эти слова не выходят никогда: игрок видит только номер места
   и имя вроде «Игрок 3». */
const ПЕРВЫЙ = МЕСТА[0];
const ВТОРОЙ = МЕСТА[1];

/* Те же названия мест, но строчными буквами. Нужны для сравнения: игрок
   может назваться «Бот-3» с большой буквы, и это должно считаться тем же
   занятым словом, что и «бот-3». Считаем один раз при запуске. */
const МЕСТА_СТРОЧНЫМИ = МЕСТА.map(function (место) { return место.toLowerCase(); });

const МИН_ИГРОКОВ = правила.МИН_ИГРОКОВ;
const МАКС_ИГРОКОВ = правила.МАКС_ИГРОКОВ;
const ИГРОКОВ_В_ПАРАХ = 4;   // игра парами бывает только вчетвером

/* Сколько знаков оставляем от имени, которым назвался игрок.
   Длиннее в список за столом всё равно не влезет, а лишние буквы — это
   лишняя память на каждой комнате и лишняя длина у каждого ответа сервера.

   Число живёт здесь, а не в комнатах, нарочно: обрезка нужна в двух местах —
   когда игрок называется (привестиИмя в комнаты.js) и когда имя выходит
   наружу вместе с событием (имяИзСобытия ниже). Две копии одного числа
   однажды разошлись бы, и второе место стало бы пропускать больше первого. */
const ДЛИНА_ИМЕНИ = 16;

/**
 * Это внутреннее название места за столом ('человек', 'бот', 'бот-3')?
 *
 * Заглавные буквы не в счёт: «Бот-3» — то же самое слово. Сравнивать
 * буква в букву тут нельзя, потому что проверки, которые ищут утечку
 * внутренних имён по словам, обычно ищут без учёта заглавных — и такое
 * имя игрока сбило бы их с толку.
 */
function этоНазваниеМеста(строка) {
  if (typeof строка !== 'string') return false;
  return МЕСТА_СТРОЧНЫМИ.indexOf(строка.trim().toLowerCase()) !== -1;
}

/** Кто соперник для этого игрока. Осмысленно только за столом на двоих. */
function соперник(игрок) {
  return игрок === ПЕРВЫЙ ? ВТОРОЙ : ПЕРВЫЙ;
}

/** Номер места за столом, 1…6. Незнакомое место — ноль. */
function номерМеста(место) {
  return МЕСТА.indexOf(место) + 1;
}

/** Как звать сидящего, если своего имени он не назвал. */
function имяПоУмолчанию(место) {
  return 'Игрок ' + номерМеста(место);
}

/** Как звать бота на этом месте. */
function имяБота(место) {
  return 'Бот ' + номерМеста(место);
}

/**
 * Раздать карты. Первый довод — кто ходит первым (после прошлой партии
 * это её проигравший), второй — настройки стола:
 *   { игроки: [места], переводной, парами, сложность }.
 * Без настроек получается прежняя партия на двоих — так её и зовут
 * старые проверки.
 */
function начатьПартию(ктоНачинает, настройки) {
  const набор = настройки && typeof настройки === 'object' ? настройки : {};
  const места = Array.isArray(набор.игроки) && набор.игроки.length >= МИН_ИГРОКОВ
    ? набор.игроки.slice()
    : [ПЕРВЫЙ, ВТОРОЙ];

  /* Игру парами просим у правил только тогда, когда за столом ровно четверо.
     Иначе правила урезали бы стол до четырёх мест — и пятый игрок пропал бы
     из партии молча. Комната до этого не доводит (она отказывается начинать
     парную игру не вчетвером), но проверка стоит и здесь: молчаливая потеря
     игрока — слишком дорогая ошибка, чтобы держать её на одном замке. */
  const партия = правила.создатьПартию({
    сложность: набор.сложность,
    игроки: места,
    переводной: набор.переводной === true,
    парами: набор.парами === true && места.length === ИГРОКОВ_В_ПАРАХ
  });

  /* Обычно первым ходит тот, у кого младший козырь, — это решают
     сами правила. Но в новой партии после реванша по обычаю «Дурака»
     первым ходит проигравший: у него есть право отыграться.
     Стол в этот момент пуст, так что менять того, кто начинает,
     совершенно безопасно. */
  if (места.indexOf(ктоНачинает) !== -1) партия.атакует = ктоНачинает;

  разложитьРуки(партия);
  return партия;
}

/**
 * Разложить карты по порядку у всех, кто за столом.
 *
 * Сами правила раскладывают только руку первого игрока (в одиночной игре
 * остальные — роботы, им порядок ни к чему). Живому человеку рука нужна
 * такая же аккуратная, поэтому раскладываем сами — сразу после раздачи
 * и после каждого добора, то есть тогда, когда карты в руке меняются
 * не по воле самого игрока. Между ходами порядок не трогаем: иначе
 * у игрока «поедут» номера карт прямо под пальцем.
 */
function разложитьРуки(партия) {
  for (const место of партия.игроки) правила.упорядочитьРуку(партия, место);
}

/** Подход закончился — карты у всех поменялись, самое время разложить руки. */
function разложитьПослеПодхода(партия) {
  if (партия.стол.length === 0) разложитьРуки(партия);
}

/**
 * Копия карты — ровно три поля и ничего больше.
 * Копируем, а не отдаём саму карту из партии: так клиенту физически
 * не может уехать что-то лишнее, если в правилах у карты появится
 * новое служебное поле.
 */
function копияКарты(карта) {
  if (!карта) return null;
  return { масть: карта.масть, имя: карта.имя, вес: карта.вес };
}

/** Пары на столе видны всем — это открытые карты. */
function копияСтола(партия) {
  return партия.стол.map(function (пара) {
    return { атака: копияКарты(пара.атака), защита: копияКарты(пара.защита) };
  });
}

/** Следующий по столу — сосед слева, даже если он уже вышел без карт. */
function следующийПоСтолу(партия, ктоЯ) {
  const где = партия.игроки.indexOf(ктоЯ);
  if (где === -1) return null;
  return партия.игроки[(где + 1) % партия.игроки.length];
}

/** Чем кончилась партия лично для этого игрока. */
function итогДляИгрока(партия, ктоЯ) {
  if (!партия.завершена) return null;
  if (партия.результат === 'ничья') return 'ничья';
  // Партия оборвалась не по картам (все вышли) — победителя нет.
  if (!партия.результат || !партия.проигравшие || партия.проигравшие.length === 0) return null;
  // В правилах проигравшие — те, кто остался дураком: один игрок, а в игре
  // парами — оба из проигравшей пары.
  return партия.проигравшие.indexOf(ктоЯ) !== -1 ? 'поражение' : 'победа';
}

