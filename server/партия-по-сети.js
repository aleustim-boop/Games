/* Сколько забранных карт называем поимённо. Больше четырёх в строку
   подсказки не влезает — то же правило, что и в игре с ботом. */
const КАРТ_СПИСКОМ = 4;

/* Случаи, которые касаются всех сразу и подлежащего не требуют вовсе. */
const ОБЩИЕ_СОБЫТИЯ = {
  'реванш': 'Играем ещё раз — карты розданы заново',
  'начали': 'Партия началась — карты розданы'
};

/**
 * Как назвать в рассказе того, кто это сделал.
 *
 * Есть два вида комнат, и зовут в них по-разному нарочно:
 *
 *   — СТАРАЯ комната на двоих (её признак — «компания» выключена).
 *     Там второй игрок всегда «Соперник»: так эта надпись выглядела
 *     с самого начала, старая страница игры имён не показывает вовсе,
 *     и менять слово в ней нельзя;
 *   — комната-КОМПАНИЯ — любая, где собирали стол руками, даже если мест
 *     в ней всего два. Там имена у всех есть и видны игроку в списке
 *     за столом, поэтому и в строке событий должно стоять имя. Иначе
 *     один человек называется на экране двумя способами разом: в списке
 *     «Боря», а в событии «Соперник» — и не сразу понятно, что это одно лицо.
 *
 * Внимание: различать эти случаи по ЧИСЛУ МЕСТ нельзя, хотя соблазн есть.
 * Так тут и было раньше, и компания на два места получала «Соперника»
 * вместо имени. Список мест приходит одинаковый в обоих случаях — имена
 * в нём есть всегда, — так что решает только признак «это компания».
 *
 * Последний довод — имя, сохранённое вместе с самим событием. Оно главнее
 * списка мест, и вот зачем: человек, вышедший из прихожей, к этой минуте
 * из комнаты уже вычеркнут, а рассказ собирается позже — искать его имя
 * в списке негде. Раньше остальные читали «Игрок 2 вышел из комнаты»,
 * хотя секунду назад видели за столом «Борю».
 */
function ктоЭтоБыл(места, кто, этоКомпания, событие) {
  if (!места || !этоКомпания) return 'Соперник';
  const сохранённое = имяИзСобытия(событие);
  if (сохранённое) return сохранённое;
  for (const место of места) {
    if (место.ключ === кто) return место.имя;
  }
  // Имени не сохранили, а место уже освободилось — зовём по номеру.
  return имяПоУмолчанию(кто);
}

/**
 * Имя, сохранённое вместе с событием, — годное или никакое.
 *
 * Проверяем его отдельно от всех прочих полей по правилу «клиенту не верим»:
 * это единственное имя в ответе, которое взято не из живого списка мест.
 * Наружу должно уходить только человеческое имя — внутреннее название места
 * ('человек', 'бот-3', да хоть «Бот-3») не должно попасть в рассказ
 * ни при какой ошибке.
 *
 * Длину обрезаем здесь же, хотя сегодня сюда и так приходит уже обрезанное
 * имя (привестиИмя в комнаты.js). Обещание «ничего лишнего отсюда не выйдет»
 * должно держаться самой проверкой, а не порядочностью соседнего файла:
 * стоит появиться второму месту, которое кладёт имя в событие, — и без этой
 * строки наружу поехала бы строка любой длины.
 */
function имяИзСобытия(событие) {
  if (!событие || typeof событие.имя !== 'string') return null;
  const имя = событие.имя.trim();
  if (!имя) return null;
  if (этоНазваниеМеста(имя)) return null;
  return имя.slice(0, ДЛИНА_ИМЕНИ);
}

/**
 * Вид последнего события одним словом: «забрал», «бито», «перевёл».
 *
 * Зачем это отдавать наружу. Текст события написан для человека и меняется
 * вместе со словами игры. Проверкам же надо знать, что случилось, и они
 * вынуждены угадывать это по словам — а от правки формулировок такие
 * проверки слепнут молча. Сегодня так и вышло: поменяли род у глаголов —
 * и сразу три проверки перестали видеть заборы карт. Вид события от слов
 * не зависит, по нему событие узнаётся наверняка.
 *
 * Наружу выходит ровно одно слово и только из наших же списков — тех
 * самых, по которым собирается текст. Незнакомое превращается в null,
 * и поля в ответе просто не будет. Всё остальное из события остаётся
 * здесь: и «кто» (внутреннее название места — 'человек', 'бот-3'),
 * и сохранённое имя игрока. Берём одно поле, а не копируем событие.
 *
 * Своё ли это слово, спрашиваем через «взятьИзСписка» — там объяснено,
 * почему обычный способ здесь не годится.
 */
function видСобытия(событие) {
  if (!событие || typeof событие.что !== 'string') return null;
  const что = событие.что;
  const наше = взятьИзСписка(РАССКАЗ_О_СОБЫТИИ, что) ||
               взятьИзСписка(ОБЩИЕ_СОБЫТИЯ, что);
  return наше ? что : null;
}

/**
 * Взять запись из списка по слову — или ничего, если такого слова там нет.
 *
 * Спрашиваем через hasOwnProperty, а не привычным «список[слово]», и это
 * единственный способ спрашивать здесь: обычная проверка отвечает «да»
 * и на общие свойства любого объекта. Придёт событие со словом «toString» —
 * и вместо рассказа вернётся чужая функция: наружу уехало бы её тело,
 * а «половинкаСКартами» на ней бы и упала.
 *
 * Через эту же дверь спрашивается и слово бота, хотя туда клиент
 * не дотягивается вовсе — слово приходит от самих правил. Так сделано
 * нарочно: «клиенту не верим» — правило про все двери сразу, а не только
 * про те, где опасно прямо сейчас. Разные способы спрашивать в одном файле
 * читаются как «здесь почему-то можно иначе», и однажды кто-то повторит
 * именно тот, что попроще.
 */
function взятьИзСписка(список, что) {
  return Object.prototype.hasOwnProperty.call(список, что) ? список[что] : null;
}

/**
 * Рассказ о последнем событии — для этого самого игрока.
 *
 * Третий довод (список мест) и четвёртый («это комната-компания») нужны
 * вместе и только затем, чтобы назвать ходившего по имени. Не передали
 * их — получается прежний рассказ комнаты на двоих, со словом «Соперник».
 */
function текстСобытия(событие, ктоЯ, места, этоКомпания, подробности) {
  if (!событие) return null;
  const общее = взятьИзСписка(ОБЩИЕ_СОБЫТИЯ, событие.что);
  if (общее) return общее;

  const своё = событие.кто === ктоЯ;
  const сКартами = половинкаСКартами(событие, ктоЯ, подробности);
  const рассказ = взятьИзСписка(РАССКАЗ_О_СОБЫТИИ, событие.что);
  if (!сКартами && !рассказ) return null;
  const половинка = сКартами || (своё ? рассказ.своё : рассказ.чужое);
  if (своё) return половинка;
  return ктоЭтоБыл(места, событие.кто, этоКомпания, событие) + ' ' + половинка;
}

/**
 * Половинка рассказа, где названы карты. Нет подробностей или чего-то
 * в них не хватает — возвращаем ничего, и рассказ остаётся прежним:
 * лучше короткая правда, чем фраза с дырой посередине.
 *
 * Довод «ктоЯ» нужен по двум причинам сразу: во-первых, для «своё» и
 * «чужое», во-вторых — рассказ уходит каждому игроку СВОЙ, и добор
 * из колоды считается для того, кто читает. В игре с ботом «вы добрали 1»
 * обращено к единственному человеку за столом; по сети такой же рассказ
 * читают четверо, и «вы» должно означать каждого из них по отдельности.
 */
function половинкаСКартами(событие, ктоЯ, подробности) {
  const шаблоны = взятьИзСписка(РАССКАЗ_С_КАРТАМИ, событие.что);
  if (!шаблоны || !подробности) return null;
  const своё = событие.кто === ктоЯ;
  let текст = своё ? шаблоны.своё : шаблоны.чужое;

  if (текст.indexOf('{карта}') !== -1) {
    if (!подробности.карта) return null;
    текст = текст.replace('{карта}', подробности.карта);
  }
  if (текст.indexOf('{покрыл}') !== -1) {
    if (!подробности.покрыл || !подробности.чем) return null;
    текст = текст.replace('{покрыл}', подробности.покрыл).replace('{чем}', подробности.чем);
  }
  if (текст.indexOf('{карт}') !== -1) {
    if (typeof подробности.карт !== 'number') return null;
    /* Винительный падеж: «забирает карты со стола — 1 карту», а не
       «1 карта». Забрать одну карту можно, и по-русски это звучит так.
       На всех прочих числах падеж ничего не меняет: «2 карты», «12 карт». */
    текст = текст.replace('{карт}', сколькоКарт(подробности.карт, true));
  }
  if (текст.indexOf('{взятое}') !== -1) {
    const имена = подробности.карты || [];
    if (typeof подробности.карт !== 'number') return null;
    /* Поимённо — только свои карты и только пока их немного: длинный список
       в строку подсказки не влезет, а число там всё равно главное. */
    текст = текст.replace('{взятое}', имена.length > 0 && имена.length <= КАРТ_СПИСКОМ
      ? имена.join(', ')
      : сколькоКарт(подробности.карт, true));
  }
  return текст + прибавкаПроДобор(подробности, ктоЯ);
}

/**
 * «, вы добрали 2» — приписка тому, кто читает. Своя у каждого игрока:
 * из колоды в конце подхода берут все, но каждому своё число.
 */
function прибавкаПроДобор(подробности, ктоЯ) {
  const добор = подробности.добор ? подробности.добор[ктоЯ] : 0;
  if (!добор || добор <= 0) return '';
  return ', вы добрали ' + добор;
}

