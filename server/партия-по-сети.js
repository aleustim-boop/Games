'use strict';

/* =====================================================================
   Партия на двоих живых игроков: тонкая прослойка между правилами
   и сетью.

   Здесь НЕТ ни одного правила игры — все они берутся из js/game.js
   обычным require. Если правило понадобится новое, его добавляют там,
   а не здесь: иначе однажды сервер и игра в браузере разойдутся,
   и найти это будет очень трудно.

   Задачи файла ровно три:
     1) начать партию для двоих;
     2) собрать «вид для игрока» — то, что можно показать именно ему
        (свои карты видит, чужие не видит вообще);
     3) выполнить намерение игрока («хочу сходить этой картой») —
        проверить его правилами и объяснить отказ человеческими словами.

   Про безопасность: вид для игрока — единственная дверь, через которую
   данные партии выходят наружу. Ни сервер, ни комнаты не имеют права
   отдавать объект партии клиенту напрямую. Тогда проверять утечку чужих
   карт нужно в одном месте, а не по всему коду.
   ===================================================================== */

const правила = require('../js/game.js');

/* Внутри правил игроки называются 'человек' и 'бот' — так сложилось
   в игре против робота. Переименовывать их в общем файле рискованно
   (там же живёт одиночная игра), поэтому здесь просто договоримся:
   создатель комнаты — «человек», второй пришедший — «бот».
   Наружу эти слова не выходят: игрок видит только «я» и «соперник». */
const ПЕРВЫЙ = 'человек';
const ВТОРОЙ = 'бот';

/** Кто соперник для этого игрока. */
function соперник(игрок) {
  return игрок === ПЕРВЫЙ ? ВТОРОЙ : ПЕРВЫЙ;
}

/**
 * Раздать карты на двоих. Уровень сложности правилам нужен только для
 * робота, а робота в игре по сети нет — передаём обычный, он ни на что
 * не влияет.
 */
function начатьПартию(ктоНачинает) {
  const партия = правила.создатьПартию('обычный');

  /* Обычно первым ходит тот, у кого младший козырь, — это решают
     сами правила. Но в новой партии после реванша по обычаю «Дурака»
     первым ходит проигравший: у него есть право отыграться.
     Стол в этот момент пуст, так что менять того, кто начинает,
     совершенно безопасно. */
  if (ктоНачинает === ПЕРВЫЙ || ктоНачинает === ВТОРОЙ) партия.атакует = ктоНачинает;

  упорядочитьРукуВторого(партия);
  return партия;
}

/**
 * Правила сами раскладывают по порядку только руку первого игрока
 * (в одиночной игре второй — робот, ему порядок ни к чему). Второму
 * живому игроку рука нужна такая же аккуратная, поэтому раскладываем её
 * сами — сразу после раздачи и после каждого добора, то есть тогда,
 * когда карты в руке меняются не по воле самого игрока. Между ходами
 * порядок не трогаем: иначе у игрока «поедут» номера карт.
 */
function упорядочитьРукуВторого(партия) {
  правила.упорядочитьРуку(партия, ВТОРОЙ);
}

/**
 * Копия карты — ровно три поля и ничего больше.
 * Копируем, а не отдаём саму карту из партии: так клиенту физически
 * не может уехать что-то лишнее, если в правилах у карты появится
 * новое служебное поле.
 */
function копияКарты(карта) {
  if (!карта) return null;
  return { масть: карта.масть, имя: карта.имя, вес: карта.вес };
}

/** Пары на столе видны обоим игрокам — это открытые карты. */
function копияСтола(партия) {
  return партия.стол.map(function (пара) {
    return { атака: копияКарты(пара.атака), защита: копияКарты(пара.защита) };
  });
}

/** Чем кончилась партия лично для этого игрока. */
function итогДляИгрока(партия, ктоЯ) {
  if (!партия.завершена) return null;
  if (партия.результат === 'ничья') return 'ничья';
  // Партия оборвалась не по картам (соперник вышел) — победителя нет.
  if (партия.результат !== ПЕРВЫЙ && партия.результат !== ВТОРОЙ) return null;
  // В правилах результат — это тот, кто остался дураком.
  return партия.результат === ктоЯ ? 'поражение' : 'победа';
}

/**
 * Событие хранится обезличенно — «кто» и «что», без имён и без карт.
 * Текст собирается отдельно для каждого игрока: одно и то же событие
 * для одного «вы взяли», для другого «соперник взял».
 */
function текстСобытия(событие, ктоЯ) {
  if (!событие) return null;
  const я = событие.кто === ктоЯ;
  switch (событие.что) {
    case 'ход':      return я ? 'Вы походили' : 'Соперник походил';
    case 'подкинул': return я ? 'Вы подкинули карту' : 'Соперник подкинул карту';
    case 'отбил':    return я ? 'Вы отбились' : 'Соперник отбился';
    case 'беру':     return я ? 'Вы берёте карты' : 'Соперник берёт карты';
    case 'бито':     return я ? 'Вы сказали «Бито»' : 'Соперник сказал «Бито»';
    case 'забрал':   return я ? 'Вы забрали карты со стола' : 'Соперник забрал карты со стола';
    case 'реванш':   return 'Играем ещё раз — карты розданы заново';
    case 'зовёт':    return я ? 'Вы предложили сыграть ещё' : 'Соперник предлагает сыграть ещё';
    case 'ушёл':     return я ? 'Вы вышли из игры' : 'Соперник вышел из игры — партия закончена';
    default:         return null;
  }
}

/**
 * Всё, что игрок имеет право знать о партии. Собирается с нуля, поле
 * за полем — никакого копирования состояния целиком, чтобы новое поле
 * в правилах не уехало клиенту само собой.
 *
 * Чего здесь нет и быть не должно:
 *   — карт соперника (только их количество);
 *   — карт колоды (только сколько осталось);
 *   — карт отбоя (только сколько там);
 *   — козырной карты после того, как её забрали из колоды.
 */
function видДляИгрока(партия, ктоЯ, добавка) {
  const вид = добавка ? Object.assign({}, добавка) : {};

  if (!партия) {
    вид.фаза = null;
    вид.мояРука = [];
    вид.картУСоперника = 0;
    вид.стол = [];
    return вид;
  }

  const колодаЦела = партия.колода.length > 0;

  вид.козырь = партия.козырь;
  // Карта под колодой лежит открытой — её видят оба. Но как только
  // колоду разобрали, она уже у кого-то в руке, и показывать её нельзя.
  вид.козырнаяКарта = колодаЦела ? копияКарты(партия.козырнаяКарта) : null;
  вид.вКолоде = партия.колода.length;
  вид.вОтбое = партия.отбой.length;

  вид.мояРука = партия.руки[ктоЯ].map(копияКарты);
  вид.картУСоперника = партия.руки[соперник(ктоЯ)].length;

  вид.стол = копияСтола(партия);
  вид.фаза = правила.фаза(партия);
  вид.яХожу = правила.ктоХодит(партия) === ктоЯ;
  вид.яАтакую = партия.атакует === ктоЯ;
  вид.берут = партия.берёт;          // защищающийся уже сказал «Беру»
  вид.завершена = партия.завершена;
  вид.итог = итогДляИгрока(партия, ктоЯ);

  /* Особый случай: партия закончилась не по картам, а потому что
     соперник вышел совсем. Ни победы, ни поражения тут нет, и клиенту
     нужно показать другой текст — поэтому и итог отдельный. */
  if (вид.завершена && !вид.итог && вид.соперникУшёл) вид.итог = 'соперник-ушёл';
  return вид;
}

/* ---------------------------------------------------------------------
   Ходы. Сервер никому не верит на слово: клиент присылает намерение,
   правила решают, можно ли так, а отказ объясняется словами.
   --------------------------------------------------------------------- */

/** Короткий ответ «нельзя, потому что…». */
function отказ(причина) {
  return { принято: false, причина: причина };
}

/**
 * Номер карты или пары. Годится только целое число не меньше нуля —
 * хоть числом, хоть строкой из цифр. Всё остальное (пусто, дробь,
 * «-1», слово, список) превращается в null, и ход будет отклонён.
 * Раньше здесь стоял обычный Number, а он превращает пустое значение
 * в ноль — и запрос без номера играл первую карту из руки.
 */
function целыйНомер(значение) {
  if (typeof значение === 'number') {
    return Number.isInteger(значение) && значение >= 0 ? значение : null;
  }
  if (typeof значение === 'string' && /^\d+$/.test(значение.trim())) {
    return Number(значение.trim());
  }
  return null;
}

/** Короткий ответ «сделано» и что об этом рассказать обоим. */
function принято(что) {
  return { принято: true, событие: что };
}

/* Названия достоинств в винительном падеже — чтобы отказ читался
   по-человечески: «подкинуть можно только шестёрку или короля». */
const НАЗВАНИЕ_ДОСТОИНСТВА = {
  '6': 'шестёрку', '7': 'семёрку', '8': 'восьмёрку', '9': 'девятку',
  '10': 'десятку', 'В': 'валета', 'Д': 'даму', 'К': 'короля', 'Т': 'туза'
};

/** «шестёрку», «шестёрку или короля», «шестёрку, короля или туза». */
function перечислить(достоинства) {
  const слова = достоинства.map(function (имя) {
    return НАЗВАНИЕ_ДОСТОИНСТВА[имя] || имя;
  });
  if (слова.length <= 1) return слова.join('');
  return слова.slice(0, -1).join(', ') + ' или ' + слова[слова.length - 1];
}

/**
 * Почему правила не дали положить карту. Сами условия здесь не
 * повторяются — берутся у правил (сколько карт на столе, сколько
 * неотбитых, какие достоинства лежат). Наше дело только назвать
 * причину словами.
 */
function почемуНельзяПоложить(партия, карта) {
  if (партия.стол.length >= правила.МАКС_КАРТ_В_ПОДХОДЕ) {
    return 'На столе уже шесть карт — больше подкидывать нельзя';
  }
  const картУЗащитника = партия.руки[правила.защищается(партия)].length;
  if (правила.неотбитых(партия) >= картУЗащитника) {
    return 'У соперника меньше карт, чем неотбитых на столе — подкидывать нечего';
  }
  const достоинства = правила.достоинстваНаСтоле(партия);
  if (достоинства.indexOf(карта.имя) === -1) {
    return 'Подкинуть можно только ' + перечислить(достоинства);
  }
  return 'Этой картой сейчас ходить нельзя';
}

/** Положить карту в атаку: первый ход подхода, подкидывание или докидывание. */
function ходКартой(партия, ктоЯ, индексКарты) {
  if (партия.атакует !== ктоЯ) return отказ('Сейчас вы отбиваетесь, а не ходите');

  const карта = партия.руки[ктоЯ][индексКарты];
  if (!карта) return отказ('Такой карты у вас нет');

  const былоНаСтоле = партия.стол.length;
  if (!правила.положитьВАтаку(партия, ктоЯ, индексКарты)) {
    return отказ(почемуНельзяПоложить(партия, карта));
  }
  return принято(былоНаСтоле === 0 ? 'ход' : 'подкинул');
}

/** Отбить карту соперника своей. */
function отбитьКарту(партия, ктоЯ, индексПары, индексКарты) {
  if (правила.фаза(партия) !== 'защита') return отказ('Сейчас отбиваться нечего');
  if (правила.защищается(партия) !== ктоЯ) return отказ('Сейчас отбивается соперник');

  const пара = партия.стол[индексПары];
  if (!пара) return отказ('Такой карты на столе нет');
  if (пара.защита) return отказ('Эта карта уже отбита');

  const карта = партия.руки[ктоЯ][индексКарты];
  if (!карта) return отказ('Такой карты у вас нет');
  if (!правила.бьёт(карта, пара.атака, партия.козырь)) {
    return отказ('Эта карта не бьёт: нужна старше той же масти или козырь');
  }
  if (!правила.отбить(партия, индексПары, индексКарты)) return отказ('Так отбиться нельзя');
  return принято('отбил');
}

/** «Беру» — отказ отбиваться. */
function взятьКарты(партия, ктоЯ) {
  if (правила.фаза(партия) !== 'защита') return отказ('Брать сейчас нечего');
  if (правила.защищается(партия) !== ктоЯ) return отказ('Сейчас отбивается соперник');
  if (!правила.объявитьБеру(партия)) return отказ('Брать сейчас нельзя');
  return принято('беру');
}

/**
 * Закончить подход. Одна кнопка на два случая, как и в игре против
 * робота: если соперник отбился — это «Бито», если он берёт —
 * это «больше не докидываю».
 */
function закончитьПодход(партия, ктоЯ) {
  const текущая = правила.фаза(партия);
  if (партия.атакует !== ктоЯ) return отказ('Подход заканчивает тот, кто ходит');
  if (текущая !== 'подкидывание' && текущая !== 'докидывание') {
    return отказ('Сейчас подход закончить нельзя: на столе есть неотбитая карта');
  }
  const заберёт = партия.берёт;
  if (!правила.завершитьПодход(партия)) return отказ('Подход уже закончен');
  упорядочитьРукуВторого(партия);   // после добора карты снова раскладываем по порядку
  return принято(заберёт ? 'забрал' : 'бито');
}

/**
 * Единственный вход для любого намерения игрока.
 * Возвращает { принято: true, событие } либо { принято: false, причина }.
 */
function сделатьХод(партия, ктоЯ, намерение) {
  if (!партия) return отказ('Партия ещё не началась');
  if (партия.завершена) return отказ('Партия уже закончена');
  if (!намерение || typeof намерение.действие !== 'string') {
    return отказ('Непонятное действие');
  }

  // Общая проверка очереди: она одинакова для всех действий и ловит
  // самый частый случай жульничества — ход за соперника.
  if (правила.ктоХодит(партия) !== ктоЯ) return отказ('Сейчас ход соперника');

  const номерКарты = целыйНомер(намерение.карта);
  const номерПары = целыйНомер(намерение.пара);

  switch (намерение.действие) {
    case 'ходить':
      if (номерКарты === null) return отказ('Не понял, какой картой вы ходите');
      return ходКартой(партия, ктоЯ, номерКарты);
    case 'отбить':
      if (номерКарты === null) return отказ('Не понял, какой картой вы отбиваетесь');
      if (номерПары === null) return отказ('Не понял, какую карту на столе вы бьёте');
      return отбитьКарту(партия, ктоЯ, номерПары, номерКарты);
    case 'беру':      return взятьКарты(партия, ктоЯ);
    case 'бито':      return закончитьПодход(партия, ктоЯ);
    default:          return отказ('Непонятное действие');
  }
}

