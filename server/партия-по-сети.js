/**
 * Кто сидит за столом — глазами этого игрока. Карт у других видно только
 * число, самих карт здесь нет и быть не может.
 *
 * Список мест приходит из комнаты (кто пришёл, кто бот, кто на связи),
 * а всё, что касается карт и очереди, добавляется тут же из партии:
 * так собранный ответ остаётся в одном месте, и утечку всегда есть где
 * искать.
 */
function ктоЗаСтолом(партия, ктоЯ, места) {
  const идётИгра = Boolean(партия) && !партия.завершена;
  const ходит = идётИгра ? правила.ктоХодит(партия) : null;
  const отбивается = идётИгра ? правила.защищается(партия) : null;

  return места.map(function (место) {
    const рука = партия ? партия.руки[место.ключ] : null;
    const напарник = партия ? правила.партнёр(партия, место.ключ) : null;
    return {
      номер: номерМеста(место.ключ),
      имя: место.имя,
      этоЯ: место.ключ === ктоЯ,
      этоБот: место.этоБот === true,
      хозяин: место.хозяин === true,
      наСвязи: место.наСвязи !== false,
      ушёл: место.ушёл === true,
      хочетЕщё: место.хочетЕщё === true,
      карт: рука ? рука.length : 0,
      ходит: место.ключ === ходит,
      отбивается: место.ключ === отбивается,
      выбыл: Boolean(партия) && !правила.вИгре(партия, место.ключ),
      проиграл: Boolean(партия && партия.завершена && партия.проигравшие &&
        партия.проигравшие.indexOf(место.ключ) !== -1),
      напарник: напарник ? номерМеста(напарник) : null
    };
  });
}

/** Есть ли в руке карта, которой сейчас можно перевести ход. */
function естьЧемПеревести(партия, ктоЯ) {
  if (!партия.переводной || партия.завершена) return false;
  if (правила.защищается(партия) !== ктоЯ) return false;
  const рука = партия.руки[ктоЯ] || [];
  for (const карта of рука) {
    if (правила.можноПеревести(партия, карта)) return true;
  }
  return false;
}

/**
 * Всё, что игрок имеет право знать о партии. Собирается с нуля, поле
 * за полем — никакого копирования состояния целиком, чтобы новое поле
 * в правилах не уехало клиенту само собой.
 *
 * Чего здесь нет и быть не должно:
 *   — карт других игроков (только их количество);
 *   — карт колоды (только сколько осталось);
 *   — карт отбоя (только сколько там);
 *   — козырной карты после того, как её забрали из колоды;
 *   — внутренних имён мест ('человек', 'бот-3' и прочих): наружу уходят
 *     только номера мест и имена вроде «Игрок 3».
 *
 * Про «места» в добавке. Комната кладёт туда сырой список сидящих —
 * с внутренними именами мест. Наружу он не уходит: здесь из него
 * собирается «застолом», а сам список выбрасывается. Комната на двоих
 * этого списка не передаёт вовсе, и ответ ей приходит ровно такой же,
 * каким был до появления игры компанией.
 */
function видДляИгрока(партия, ктоЯ, добавка) {
  const вид = добавка ? Object.assign({}, добавка) : {};
  const места = вид.места || null;
  delete вид.места;

  if (!партия) {
    вид.фаза = null;
    вид.мояРука = [];
    вид.картУСоперника = 0;
    вид.стол = [];
    if (места) вид.застолом = ктоЗаСтолом(null, ктоЯ, места);
    return вид;
  }

  const колодаЦела = партия.колода.length > 0;
  const сосед = следующийПоСтолу(партия, ктоЯ);

  вид.козырь = партия.козырь;
  // Карта под колодой лежит открытой — её видят все. Но как только
  // колоду разобрали, она уже у кого-то в руке, и показывать её нельзя.
  вид.козырнаяКарта = колодаЦела ? копияКарты(партия.козырнаяКарта) : null;
  вид.вКолоде = партия.колода.length;
  вид.вОтбое = партия.отбой.length;

  вид.мояРука = (партия.руки[ктоЯ] || []).map(копияКарты);
  /* Сколько карт у соседа слева. За столом на двоих это и есть соперник —
     поле осталось с тех времён и так же называется. В компании смотреть
     надо в «застолом»: там счёт карт у каждого. */
  вид.картУСоперника = сосед && партия.руки[сосед] ? партия.руки[сосед].length : 0;

  вид.стол = копияСтола(партия);
  вид.фаза = правила.фаза(партия);
  вид.яХожу = правила.ктоХодит(партия) === ктоЯ;
  вид.яАтакую = партия.атакует === ктоЯ;
  вид.берут = партия.берёт;          // отбивающийся уже сказал «Беру»
  вид.завершена = партия.завершена;
  вид.итог = итогДляИгрока(партия, ктоЯ);

  /* Особый случай: партия закончилась не по картам, а потому что
     соперник вышел совсем. Ни победы, ни поражения тут нет, и клиенту
     нужно показать другой текст — поэтому и итог отдельный. */
  if (вид.завершена && !вид.итог && вид.соперникУшёл) вид.итог = 'соперник-ушёл';

  if (места) {
    вид.застолом = ктоЗаСтолом(партия, ктоЯ, места);
    вид.яОтбиваюсь = правила.защищается(партия) === ктоЯ;
    вид.могуПодкинуть = правила.можетПодкидывать(партия, ктоЯ);
    вид.могуПеревести = естьЧемПеревести(партия, ктоЯ);
    // Разновидность игры берём у самой партии, а не у комнаты: там правда.
    вид.переводной = партия.переводной === true;
    вид.парами = партия.парами === true;
  }
  return вид;
}

/* ---------------------------------------------------------------------
   Ходы. Сервер никому не верит на слово: клиент присылает намерение,
   правила решают, можно ли так, а отказ объясняется словами.
   --------------------------------------------------------------------- */

/** Короткий ответ «нельзя, потому что…». */
function отказ(причина) {
  return { принято: false, причина: причина };
}

/**
 * Номер карты или пары. Годится только целое число не меньше нуля —
 * хоть числом, хоть строкой из цифр. Всё остальное (пусто, дробь,
 * «-1», слово, список) превращается в null, и ход будет отклонён.
 * Раньше здесь стоял обычный Number, а он превращает пустое значение
 * в ноль — и запрос без номера играл первую карту из руки.
 */
function целыйНомер(значение) {
  if (typeof значение === 'number') {
    return Number.isInteger(значение) && значение >= 0 ? значение : null;
  }
  if (typeof значение === 'string' && /^\d+$/.test(значение.trim())) {
    return Number(значение.trim());
  }
  return null;
}

/**
 * Короткий ответ «сделано» и что об этом рассказать остальным.
 *
 * Второй довод — с кем это случилось. Обычно это тот же, кто ходил,
 * и его называть незачем. Но один случай выбивается: карты со стола
 * забирает отбивавшийся, а кнопку «Готово» нажимает подкидывающий.
 * Тогда событие надо приписать отбивавшемуся, иначе игра пишет
 * «Вы забрали карты» человеку, который ничего не забирал.
 */
function принято(что, ктоСделал) {
  const ответ = { принято: true, событие: что };
  if (ктоСделал) ответ.ктоСделал = ктоСделал;
  return ответ;
}

/* Названия достоинств в винительном падеже — чтобы отказ читался
   по-человечески: «подкинуть можно только шестёрку или короля». */
const НАЗВАНИЕ_ДОСТОИНСТВА = {
  '2': 'двойку', '3': 'тройку', '4': 'четвёрку', '5': 'пятёрку',
  '6': 'шестёрку', '7': 'семёрку', '8': 'восьмёрку', '9': 'девятку',
  '10': 'десятку', 'В': 'валета', 'Д': 'даму', 'К': 'короля', 'Т': 'туза'
};

/** «шестёрку», «шестёрку или короля», «шестёрку, короля или туза». */
function перечислить(достоинства) {
  const слова = достоинства.map(function (имя) {
    return НАЗВАНИЕ_ДОСТОИНСТВА[имя] || имя;
  });
  if (слова.length <= 1) return слова.join('');
  return слова.slice(0, -1).join(', ') + ' или ' + слова[слова.length - 1];
}

/**
 * Почему правила не дали положить карту. Сами условия здесь не
 * повторяются — берутся у правил (сколько карт на столе, сколько
 * неотбитых, какие достоинства лежат). Наше дело только назвать
 * причину словами.
 */
function почемуНельзяПоложить(партия, карта) {
  if (партия.стол.length >= правила.МАКС_КАРТ_В_ПОДХОДЕ) {
    return 'На столе уже шесть карт — больше подкидывать нельзя';
  }
  const картУЗащитника = партия.руки[правила.защищается(партия)].length;
  if (правила.неотбитых(партия) >= картУЗащитника) {
    return 'У того, кто отбивается, меньше карт, чем неотбитых на столе — подкидывать нечего';
  }
  const достоинства = правила.достоинстваНаСтоле(партия);
  if (достоинства.indexOf(карта.имя) === -1) {
    return 'Подкинуть можно только ' + перечислить(достоинства);
  }
  return 'Этой картой сейчас ходить нельзя';
}

/** Положить карту в атаку: первый ход подхода, подкидывание или докидывание. */
function ходКартой(партия, ктоЯ, индексКарты) {
  if (!правила.можетПодкидывать(партия, ктоЯ)) {
    if (партия.стол.length === 0) return отказ('Сейчас ходит другой игрок');
    return партия.парами
      ? отказ('Подкидывать может только соперник того, кто отбивается, — напарнику не подкидывают')
      : отказ('Сейчас вы отбиваетесь, а не ходите');
  }

  const карта = партия.руки[ктоЯ][индексКарты];
  if (!карта) return отказ('Такой карты у вас нет');

  const былоНаСтоле = партия.стол.length;
  if (!правила.положитьВАтаку(партия, ктоЯ, индексКарты)) {
    return отказ(почемуНельзяПоложить(партия, карта));
  }
  return принято(былоНаСтоле === 0 ? 'ход' : 'подкинул');
}

/** Отбить карту соперника своей. */
function отбитьКарту(партия, ктоЯ, индексПары, индексКарты) {
  if (правила.фаза(партия) !== 'защита') return отказ('Сейчас отбиваться нечего');
  if (правила.защищается(партия) !== ктоЯ) return отказ('Сейчас отбивается другой игрок');

  const пара = партия.стол[индексПары];
  if (!пара) return отказ('Такой карты на столе нет');
  if (пара.защита) return отказ('Эта карта уже отбита');

  const карта = партия.руки[ктоЯ][индексКарты];
  if (!карта) return отказ('Такой карты у вас нет');
  if (!правила.бьёт(карта, пара.атака, партия.козырь)) {
    return отказ('Эта карта не бьёт: нужна старше той же масти или козырь');
  }
  if (!правила.отбить(партия, индексПары, индексКарты)) return отказ('Так отбиться нельзя');
  return принято('отбил');
}

/**
 * Почему не дали перевести. Условия перевода живут в правилах
 * (можноПеревести), здесь только слова к каждому из них.
 */
function почемуНельзяПеревести(партия, карта) {
  if (правила.неотбитых(партия) !== партия.стол.length) {
    return 'Переводить поздно: вы уже отбили карту в этом подходе';
  }
  if (партия.стол.length >= правила.МАКС_КАРТ_В_ПОДХОДЕ) {
    return 'На столе уже шесть карт — переводить некуда';
  }
  if (правила.достоинстваНаСтоле(партия).indexOf(карта.имя) === -1) {
    return 'Перевести можно только ' + перечислить(правила.достоинстваНаСтоле(партия));
  }
  return 'У следующего игрока слишком мало карт — ему такой стол не отбить';
}

/** Перевод: вместо защиты кладём карту того же достоинства соседу. */
function перевестиХод(партия, ктоЯ, индексКарты) {
  if (!партия.переводной) return отказ('В этой партии перевод не играется');
  if (правила.фаза(партия) !== 'защита') return отказ('Переводить сейчас нечего');
  if (правила.защищается(партия) !== ктоЯ) return отказ('Сейчас отбивается другой игрок');

  const карта = партия.руки[ктоЯ][индексКарты];
  if (!карта) return отказ('Такой карты у вас нет');
  if (!правила.перевести(партия, индексКарты)) {
    return отказ(почемуНельзяПеревести(партия, карта));
  }
  return принято('перевёл');
}

/** «Беру» — отказ отбиваться. */
function взятьКарты(партия, ктоЯ) {
  if (правила.фаза(партия) !== 'защита') return отказ('Брать сейчас нечего');
  if (правила.защищается(партия) !== ктоЯ) return отказ('Сейчас отбивается другой игрок');
  if (!правила.объявитьБеру(партия)) return отказ('Брать сейчас нельзя');
  return принято('беру');
}

/**
 * Закончить подход. Одна кнопка на три случая, как и в игре против
 * робота: соперник отбился — это «Бито», соперник берёт — это «больше
 * не докидываю», а за столом втроём и больше — ещё и «я пас, пусть
 * решают остальные».
 *
 * Кто решает, закончился ли подход, — сами правила: пока хоть кто-то
 * из круга ещё не отказался подкидывать, подход продолжается. Поэтому
 * здесь зовётся «пас», а не «завершить подход»: вдвоём это одно и то же,
 * а в компании разница принципиальная.
 */
function закончитьПодход(партия, ктоЯ) {
  const текущая = правила.фаза(партия);
  if (текущая !== 'подкидывание' && текущая !== 'докидывание') {
    return отказ('Сейчас подход закончить нельзя: на столе есть неотбитая карта');
  }
  if (!правила.можетПодкидывать(партия, ктоЯ)) {
    return отказ('Подход заканчивает тот, кто ходит');
  }
  const заберёт = партия.берёт;
  /* Кто заберёт стол, спрашиваем ДО «паса». Пас может закончить подход
     тут же: ход перейдёт другому игроку, и «кто отбивается» станет уже
     другим человеком. Спроси мы после — событие досталось бы соседу
     забравшего, и игрок читал бы про себя чужой ход. */
  const ктоЗаберёт = правила.защищается(партия);
  if (!правила.пас(партия, ктоЯ)) return отказ('Подход уже закончен');
  // Стол опустел — значит, подход и правда закончился, а не просто
  // перешло слово к следующему подкидывающему.
  if (партия.стол.length > 0) return принято('пас');
  разложитьРуки(партия);   // после добора карты снова раскладываем по порядку
  // «Бито» говорит тот, кто закончил подход, а карты забирает отбивавшийся.
  return заберёт ? принято('забрал', ктоЗаберёт) : принято('бито');
}

/**
 * Единственный вход для любого намерения игрока.
 * Возвращает { принято: true, событие } либо { принято: false, причина }.
 *
 * К согласию иногда добавляется третье поле — «ктоСделал». Это место за
 * столом, с которым событие случилось на самом деле. Появляется оно
 * только тогда, когда это не тот, кто ходил, а такое бывает в одном
 * случае: подход заканчивает подкидывающий, а карты со стола забирает
 * отбивавшийся. Кто рассказывает о событии остальным — берёт имя отсюда,
 * а не имя ходившего, иначе игра напишет «Вы забрали карты» человеку,
 * который ничего не забирал. Поля нет — значит, событие случилось с тем,
 * кто ходил.
 */
function сделатьХод(партия, ктоЯ, намерение) {
  if (!партия) return отказ('Партия ещё не началась');
  if (партия.завершена) return отказ('Партия уже закончена');
  if (!намерение || typeof намерение.действие !== 'string') {
    return отказ('Непонятное действие');
  }
  if (!правила.вИгре(партия, ктоЯ)) {
    return отказ('Вы вышли из этой партии — у вас кончились карты');
  }

  // Общая проверка очереди: она одинакова для всех действий и ловит
  // самый частый случай жульничества — ход за другого игрока.
  if (правила.ктоХодит(партия) !== ктоЯ) return отказ('Сейчас ход другого игрока');

  const номерКарты = целыйНомер(намерение.карта);
  const номерПары = целыйНомер(намерение.пара);

  switch (намерение.действие) {
    case 'ходить':
      if (номерКарты === null) return отказ('Не понял, какой картой вы ходите');
      return ходКартой(партия, ктоЯ, номерКарты);
    case 'отбить':
      if (номерКарты === null) return отказ('Не понял, какой картой вы отбиваетесь');
      if (номерПары === null) return отказ('Не понял, какую карту на столе вы бьёте');
      return отбитьКарту(партия, ктоЯ, номерПары, номерКарты);
    case 'перевести':
      if (номерКарты === null) return отказ('Не понял, какой картой вы переводите');
      return перевестиХод(партия, ктоЯ, номерКарты);
    case 'беру':      return взятьКарты(партия, ктоЯ);
    case 'бито':      return закончитьПодход(партия, ктоЯ);
    default:          return отказ('Непонятное действие');
  }
}

/* ---------------------------------------------------------------------
   Ход бота. Бот тут тот же самый, что и в игре без сети, — правила
   ходят за него сами. Наше дело маленькое: позвать их в свою очередь
   и перевести короткое слово бота в название события, понятное клиенту.
   --------------------------------------------------------------------- */

/* Пауза перед ходом бота. Мгновенный ход выглядит так, будто карты
   легли сами: человек не успевает заметить, что произошло. Столько же
   ждёт бот в игре без сети. */
const ПАУЗА_БОТА = 700;

/* Что бот сделал (его словами) → как это назвать в рассказе. */
const СЛОВО_БОТА = {
  'ходит': 'ход',
  'подкидывает': 'подкинул',
  'отбивается': 'отбил',
  'переводит': 'перевёл',
  'беру': 'беру',
  'бито': 'бито',
  'пас': 'бито',
  'не подкидывает': 'пас'
};

/** Чей сейчас ход. null — если партии нет или она уже кончена. */
function чейХод(партия) {
  if (!партия || партия.завершена) return null;
  return правила.ктоХодит(партия);
}

/**
 * Сходить за бота один раз. Возвращает { событие, ктоСделал } или null,
 * если ходить было не его очередь.
 *
 * Заметьте, что событие определяется не только по слову бота, но и по
 * столу: если после хода стол опустел, значит подход закончился, и людям
 * надо сказать «Бито» или «забрал карты», а не «больше не подкидываю».
 *
 * «Ктосделал» почти всегда сам бот. Исключение одно и то же, что и у
 * живого игрока: закончить подход может подкидывающий, а карты со стола
 * достаются тому, кто отбивался.
 */
function ходЗаБота(партия, место, уровень) {
  if (!партия || партия.завершена) return null;
  if (правила.ктоХодит(партия) !== место) return null;

  const былоНаСтоле = партия.стол.length;
  const заберёт = партия.берёт;
  const фазаБыла = правила.фаза(партия);
  /* Кто отбивается — запоминаем до хода бота: после конца подхода
     ход уходит другому, и этот же вопрос даст уже другой ответ. */
  const ктоОтбивается = правила.защищается(партия);

  const слово = правила.ходБота(партия, место, уровень);
  let событие = СЛОВО_БОТА[слово] || null;
  let ктоСделал = место;
  if (былоНаСтоле > 0 && партия.стол.length === 0) {
    событие = заберёт ? 'забрал' : 'бито';
    if (заберёт) ктоСделал = ктоОтбивается;
  }

  /* Бот не придумал хода — такого быть не должно, но партия не имеет
     права зависнуть из-за одной странности. Делаем самый безопасный
     ход теми же правилами: отбиваться нечем — берём, ходить нечем —
     заканчиваем подход. */
  if (!событие) {
    const запас = сделатьХод(партия, место,
      { действие: фазаБыла === 'защита' ? 'беру' : 'бито' });
    if (!запас.принято) return null;
    событие = запас.событие;
    ктоСделал = запас.ктоСделал || место;
  }

  разложитьПослеПодхода(партия);
  return { событие: событие, ктоСделал: ктоСделал };
}

