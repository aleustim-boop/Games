function выключено(имя) {
  const значение = process.env[имя];
  return typeof значение === 'string' && /^(выкл|off)$/i.test(значение.trim());
}

/** Целое из окружения в границах; чужое значение — умолчание. */
function целоеИзОкружения(имя, умолчание, мин, макс) {
  const строка = process.env[имя];
  if (typeof строка !== 'string' || !/^\d{1,6}$/.test(строка.trim())) return умолчание;
  const число = Number(строка.trim());
  return число >= мин && число <= макс ? число : умолчание;
}

/** Столов на игру: таблица «игра:число» из окружения поверх умолчаний. */
function столовНаИгру() {
  const итог = Object.assign({}, СТОЛОВ_ПО_УМОЛЧАНИЮ);
  const строка = process.env.ЛОББИ_СТОЛОВ;
  if (typeof строка !== 'string') return итог;
  for (const часть of строка.split(',')) {
    const пара = часть.split(':');
    if (пара.length !== 2) continue;
    const игра = пара[0].trim();
    const число = пара[1].trim();
    if (!реестр.договорЕсть(игра) || !/^\d$/.test(число)) continue;
    if (Number(число) > ПРЕДЕЛ_СТОЛОВ_НА_ИГРУ) continue;
    итог[игра] = Number(число);
  }
  return итог;
}

function настройки() {
  return {
    столыВыключены: выключено('ЛИЧИНЫ') || выключено('ЛОББИ_ЛИЧИН'),
    максЛичин: целоеИзОкружения('ЛОББИ_МАКС_ЛИЧИН', УМОЛЧАНИЕ_МАКС_ЛИЧИН, 0, личины.все().length),
    порогЛюдей: целоеИзОкружения('ЛОББИ_ПОРОГ_ЛЮДЕЙ', УМОЛЧАНИЕ_ПОРОГ_ЛЮДЕЙ, 1, ПРЕДЕЛ_ПОРОГА),
    столовНаИгру: столовНаИгру()
  };
}

