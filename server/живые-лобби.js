/* =====================================================================
   ЖИВЫЕ ЛОББИ: режиссёр столов личин (этап Э4, штаб/план-живые-лобби.md).

   Чтобы «Найти игру» не пустовало, пока людей мало, сервер сам держит
   открытые столы, за которыми уже сидят личины (server/личины.js) и ждут
   гостей. Этот модуль — режиссёр: раз в 5–10 секунд он смотрит, каких
   столов не хватает, открывает недостающие, а столы, за которыми никто
   не сел слишком долго, «устают ждать» и закрываются — новый стол той же
   игры появляется через 30–120 секунд, поэтому список не мигает разом.

   Сами двери (создать, закрыть, узнать состояние) — в server/комнаты.js.
   Здесь только расписание и расчёт. Режиссёр ничего не знает про сеть и
   Telegram: комнаты и счётчик людей ему подают в запустить().

   Решения владельца (по умолчанию):
     — владелец 09.10: ботов мало — 80 личин, за столами всего до 40;
     — по одному столу на видимую игру, в дураке — три; спрятанным играм
       и «Захвату» столов нет;
     — людей 30 и больше: новые столы не открываем, лишние пустые
       закрываем по одному за шаг.

   Выключатели (читаются на каждом шаге, поэтому действуют сразу):
     ЛИЧИНЫ=выкл       — личин нет вовсе: пустые столы закрываются, новых нет;
     ЛОББИ_ЛИЧИН=выкл  — только столы личин (подбор с личинами остаётся).
   Числа (неверные значения отбрасываются, остаётся умолчание):
     ЛОББИ_МАКС_ЛИЧИН=40          сколько личин всего за столами (0–всего личин)
     ЛОББИ_ПОРОГ_ЛЮДЕЙ=30         при стольких людях новых столов нет (1–10000)
     ЛОББИ_СТОЛОВ=дурак:2,шашки:1 столов на игру (0–3); не названные — по умолчанию
                                 спрятанной игре (поле «спрятана» в js/игры-реестр.js) столы не ставятся, даже если она названа в ЛОББИ_СТОЛОВ; не названная в умолчаниях игра — 0 столов
   ===================================================================== */

const личины = require('./личины.js');
const реестр = require('./игры/реестр.js');
const реестрВитрины = require('../js/игры-реестр.js');   // оттуда читаем поле «спрятана»

const ШАГ_ОТ_МС = 5000;              // между шагами режиссёра — 5–10 секунд
const ШАГ_ДО_МС = 10000;
const ПЕРВЫЙ_ШАГ_МС = 2000;          // после запуска первый шаг — быстро
const ПАУЗА_НОВОГО_ОТ_МС = 30000;    // новый стол игры после закрытия — через 30–120 с
const ПАУЗА_НОВОГО_ДО_МС = 120000;
const ПАУЗА_ПОСЛЕ_ОТКАЗА_МС = 60000; // не вышло открыть — игра отдыхает минуту
const ОТКРЫТИЙ_ЗА_ШАГ = 3;          // с запуска сервера список наполняется постепенно

const УМОЛЧАНИЕ_МАКС_ЛИЧИН = 40;
const УМОЛЧАНИЕ_ПОРОГ_ЛЮДЕЙ = 30;
const ПРЕДЕЛ_ПОРОГА = 10000;
const ПРЕДЕЛ_СТОЛОВ_НА_ИГРУ = 3;

/* Сколько столов на игру по умолчанию: владелец 09.10 — ботов мало.
   Дурак — 3 стола, остальным видимым играм по одному. Спрятанным (поле
   «спрятана» в js/игры-реестр.js) столов нет вовсе — см. цельСтолов.
   «Захват» — 0: раунд одновременный, и в пробе самоигры без комнаты
   (боты вдвоём и втроём) партия не двигалась; пока не проверена в комнате,
   стол личин ему не ставим (включается ЛОББИ_СТОЛОВ=захват:1). */
const СТОЛОВ_ПО_УМОЛЧАНИЮ = {
  'дурак': 3, 'шашки': 1, 'шахматы': 1, 'нарды': 1, 'деберц': 1,
  'морской-бой': 1, 'домино': 1, 'захват': 0,
  // до проверки вживую: бот катана может вернуть «хода нет», стол встанет до часов;
  // включается ЛОББИ_СТОЛОВ=катан:1
  'катан': 0
};

/** Спрятана ли игра с витрины. Источник один: js/игры-реестр.js (список не зашит). */
function игруСпрятали(игра) {
  const запись = реестрВитрины.поКлючу(игра);
  return !!(запись && запись.спрятана);
}

/** Сколько столов нужно игре сейчас: спрятанной — ни одного, иначе по настройке (не названная — 0, пока не проверена). */
function цельСтолов(игра, таблица) {
  if (игруСпрятали(игра)) return 0;
  return таблица[игра] === undefined ? 0 : таблица[игра];
}

/* Формы стола: сколько мест и сколько из них занимают личины (остальные —
   гостям). Столов больше, чем форм, — формы идут по кругу. Игра, которой
   здесь нет, получает самый маленький стол из одной личины. */
const ФОРМЫ = {
  'дурак': [{ мест: 2, сколькоЛичин: 1 }, { мест: 4, парами: true, сколькоЛичин: 2 }],
  'монополия': [{ мест: 3, сколькоЛичин: 1 }, { мест: 4, сколькоЛичин: 2 }],
  'катан': [{ мест: 3, сколькоЛичин: 1 }],
  'покер': [{ мест: 3, сколькоЛичин: 1 }]
};

let комнаты = null;          // модуль комнат (подают в запустить)
let подсчётЛюдей = null;     // () => число живых людей (комнаты с людьми + ищущие)
let таймер = null;
let запущен = false;
let пул = [];                // личины, которым разрешено сидеть за столами режиссёра
let размерПула = -1;
let столы = new Map();       // код → { код, игра, личины, закрытьС }
let разрешеноС = new Map();  // игра → время, раньше которого новый стол не открываем
let отпущенные = new Map();  // код → стол: за ним сел человек, режиссёр его не ведёт, но следит

