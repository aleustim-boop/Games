'use strict';

/* =====================================================================
   Шлагбаум: притормаживает подбор кодов комнат.

   Зачем. Код комнаты короткий — четыре знака, его диктуют другу
   голосом. Всего таких кодов около миллиона, и машина, если ей не
   мешать, перебирает их со скоростью десять тысяч в секунду —
   то есть находит чужую комнату за полторы минуты. Пока сервер стоит
   дома, это никого не касается, но в интернете к людям начнут
   подсаживаться посторонние.

   Удлинять код нельзя: каждый лишний знак — это ошибка при передаче
   голосом. Поэтому мешаем иначе — задержкой ответа.

   Главное правило, ради которого шлагбаум переделан: ждёт тот, кто
   ошибается, и только он. Раньше было не так — задержку считали
   по большему из двух счётчиков (своему и общему по серверу), а сами
   попытки стояли в одной очереди на весь сервер. Из-за этого один
   перебиратель заставлял ждать всех, а десять перебирателей закрывали
   вход честному игроку совсем: паузы не перекрывались, а складывались.
   Замер тестировщика показал 30 секунд ожидания у человека, который
   набрал код правильно и не ошибся ни разу.

   Как устроено сейчас:

     1. Неудачи считаются по адресу того, кто ошибся. У кого неудач нет,
        тот не ждёт ничего и даже не заводит записи в памяти.

     2. Первые несколько неудач прощаются: живой человек ошибается
        в коде два-три раза, и он не должен ничего ждать. Дальше
        задержка удваивается с каждой неудачей — до потолка, который
        заведомо ниже, чем терпение браузера игры.

     3. Пауза каждому отсыпается своя, параллельно с чужими. Чтобы
        перебиратель не обошёл задержку в сорок потоков, с одного адреса
        одновременно держим под паузой лишь несколько попыток, остальным
        сразу отвечаем отказом — это нам ничего не стоит.

     4. Неудачи забываются по одной в секунду: перестал ошибаться —
        шлагбаум поднялся сам. Больше счёт не обнуляет ничто.

        Раньше счёт адреса стирал удачный вход, и это оказалось дырой:
        хватало двух адресов, чтобы перебирать коды без остановки.
        С первого создаём комнату, со второго угадываем коды и входим
        в эту комнату по настоящему коду — счёт второго адреса
        обнулялся, и снова доступны бесплатные попытки. Живому человеку
        прощение при входе не нужно вовсе: чтобы исчерпать пять
        прощённых неудач, надо ошибиться пять раз меньше чем за пять
        секунд, а на набор кода с голоса уходит больше.

     5. Аварийный клапан — на случай, когда ломятся сразу с сотен адресов.
        Счёт по адресу тут бессилен: у каждой попытки адрес новый, и
        записи на него ещё нет. Поэтому при явно ненормальном ОБЩЕМ
        напоре мы, во-первых, перестаём прощать промахи авансом,
        а во-вторых, придерживаем КАЖДУЮ попытку входа на небольшую
        паузу и ограничиваем, сколько таких пауз идёт разом. Честный
        игрок платит за это одну паузу заметно меньше секунды, а перебор
        со сменой адресов упирается в потолок «сколько ждут разом».
   ===================================================================== */

/* Столько неудач прощаем без задержки — с запасом на опечатки живого
   человека, который набирает код с голоса. */
const ПРОЩАЕМ_НЕУДАЧ = 5;

/* Первая задержка после исчерпания прощённых попыток и потолок,
   выше которого не поднимаемся.

   Потолок выбран не «на глаз»: браузер игры ждёт короткий ответ
   10 секунд (ОБЫЧНОЕ_ОЖИДАНИЕ в js/сеть.js), а всё, что дольше,
   человек видит как «Сервер игры не отвечает». Три секунды оставляют
   запас и на сеть, и на медленный телефон. Задержка, из-за которой
   честный игрок бросает запрос, хуже, чем отсутствие задержки. */
const ПЕРВАЯ_ЗАДЕРЖКА = 250;
const ПОТОЛОК_ЗАДЕРЖКИ = 3000;

/* За это время забывается одна неудача.

   Раньше здесь стояло три секунды, и тормоз сам себя поддерживал:
   при задержке в четыре секунды новые неудачи копились не медленнее,
   чем забывались старые. Секунда забывания против доросшей до секунды
   задержки — это равновесие примерно на одной попытке подбора в секунду
   с адреса, а человеку, который трижды промахнулся мимо кода, всё
   прощается за несколько секунд. */
const ЗАБЫВАЕМ_НЕУДАЧУ_ЗА = 1000;

/* Сколько попыток с ОДНОГО адреса могут ждать свою паузу одновременно.
   Больше — сразу отказ, не разбирая кода.

   Это замена прежней общей очереди. Смысл тот же (перебор в сорок
   потоков не должен идти в сорок раз быстрее), но платит за него только
   тот адрес, с которого ломятся: чужие паузы теперь не складываются,
   и дольше потолка никто не ждёт. Живому человеку столько и не нужно —
   он нажимает «Войти» один раз, ну два. */
const ПРЕДЕЛ_ОЧЕРЕДИ = 4;

/* Аварийный клапан: столько неудач по всему серверу разом — это уже
   не опечатки живых людей, а перебор с многих адресов. Двести неправильных
   кодов при том, что общий счёт тает по пять штук в секунду, — это напор
   больше пяти ошибок в секунду на весь сервер. У домашней игры на триста
   комнат такого не бывает.

   При открытом клапане мы делаем две вещи: перестаём прощать промахи
   авансом и придерживаем каждую попытку входа на общую паузу. */
const НЕНОРМАЛЬНЫЙ_НАПОР = 200;
const ПРОЩАЕМ_ПРИ_НАПОРЕ = 0;

/* Общий счёт тает быстрее личного: он копит промахи всего сервера, и одна
   отбитая атака не должна держать клапан открытым полдня. Пять в секунду —
   это и порог «нормального» напора, и скорость, с которой сервер приходит
   в себя после атаки. */
const ЗАБЫВАЕМ_ОБЩУЮ_НЕУДАЧУ_ЗА = 200;

/* Выше этого общий счёт не растёт. Иначе после минуты атаки в двести
   попыток в секунду он дорос бы до десятков тысяч, и клапан остался бы
   открытым на часы — а платят за открытый клапан все, в том числе
   честные игроки. С этим потолком сервер приходит в себя за две минуты. */
const ПОТОЛОК_ОБЩЕГО_СЧЁТА = 4 * НЕНОРМАЛЬНЫЙ_НАПОР;

/* Общая пауза при открытом клапане: с неё начинаем и до неё же растём,
   удваивая на каждый лишний «напор». Потолок выбран так, чтобы честный
   игрок в худшем случае ждал секунду — вчетверо меньше, чем терпение
   браузера игры. */
const ОБЩАЯ_ПАУЗА = 150;
const ПОТОЛОК_ОБЩЕЙ_ПАУЗЫ = 1000;

/* Сколько попыток входа могут ждать паузу одновременно ПО ВСЕМУ серверу.
   Это и есть потолок скорости перебора со сменой адресов: больше, чем
   «столько попыток за одну паузу», не пройдёт никто. Остальным сразу
   отвечаем отказом — он ничего не стоит и кода не проверяет.

   Шестьдесят — с большим запасом для живых людей: пауза вообще бывает
   только у того, кто уже ошибался, либо при открытом клапане, а вход
   человек делает один раз за партию. */
const ПРЕДЕЛ_ОЧЕРЕДИ_ВСЕГО = 60;

/* Больше стольких адресов не помним — иначе память будет расти
   от одних только случайных гостей. */
const ПОМНИМ_АДРЕСОВ = 2000;

/* Счётчики: общий по серверу и по каждому провинившемуся адресу.
   Записи заводятся только на тех, кто ошибся: у кого неудач нет,
   тому и помнить нечего. Скорость забывания у каждого счёта своя —
   она лежит прямо в нём, чтобы её не приходилось таскать по вызовам. */
const общийСчёт = { неудач: 0, когда: Date.now(), забываемЗа: ЗАБЫВАЕМ_ОБЩУЮ_НЕУДАЧУ_ЗА };
const поАдресам = new Map();

/* Сколько попыток прямо сейчас отсиживают свою паузу — по всему серверу.
   Нужно только для проверок: по этому числу видно, что сервер пуст. */
let ждутСейчас = 0;

function ключАдреса(адрес) {
  return адрес || 'неизвестно';
}

/** Сколько неудач числится сейчас. Ничего не меняет — только считает. */
function неудачНаСейчас(счёт, сейчас) {
  const забыто = Math.floor((сейчас - счёт.когда) / счёт.забываемЗа);
  return Math.max(0, счёт.неудач - забыто);
}

/**
 * То же самое, но забытое действительно списывается со счёта.
 * Остаток времени не выбрасываем: иначе при частых обращениях
 * забывание всё время начиналось бы заново и не работало вовсе.
 */
function списатьЗабытое(счёт, сейчас) {
  const забыто = Math.floor((сейчас - счёт.когда) / счёт.забываемЗа);
  if (забыто > 0) {
    счёт.неудач = Math.max(0, счёт.неудач - забыто);
    счёт.когда = счёт.неудач === 0 ? сейчас : счёт.когда + забыто * счёт.забываемЗа;
  }
  return счёт.неудач;
}

/** Счёт по адресу; заводим только когда есть что записать. */
function счётАдреса(адрес) {
  const ключ = ключАдреса(адрес);
  let счёт = поАдресам.get(ключ);
  if (!счёт) {
    if (поАдресам.size >= ПОМНИМ_АДРЕСОВ) освободитьМесто();
    счёт = { неудач: 0, когда: Date.now(), ждут: 0, забываемЗа: ЗАБЫВАЕМ_НЕУДАЧУ_ЗА };
    поАдресам.set(ключ, счёт);
  }
  return счёт;
}

/**
 * Освободить место в памяти под новые адреса.
 *
 * Сначала выкидываем тех, за кем уже ничего не числится. Но если ломятся
 * разом с двух тысяч адресов, таких не найдётся ни одного — раньше карта
 * в этом случае продолжала расти, и каждый новый адрес запускал полный
 * обход всех записей. Поэтому вторым заходом выбрасываем самые старые
 * записи: Map хранит их в порядке появления, значит, первые в обходе —
 * они и есть. Тех, кто прямо сейчас отсиживает паузу, не трогаем.
 */
function освободитьМесто() {
  const сейчас = Date.now();
  for (const [ключ, счёт] of поАдресам) {
    if (счёт.ждут === 0 && списатьЗабытое(счёт, сейчас) === 0) поАдресам.delete(ключ);
  }
  if (поАдресам.size < ПОМНИМ_АДРЕСОВ) return;

  // Чистим сразу с запасом, чтобы не обходить всю карту на каждом новом адресе.
  let выкинуть = поАдресам.size - ПОМНИМ_АДРЕСОВ + Math.ceil(ПОМНИМ_АДРЕСОВ / 10);
  for (const [ключ, счёт] of поАдресам) {
    if (выкинуть <= 0) break;
    if (счёт.ждут > 0) continue;
    поАдресам.delete(ключ);
    выкинуть--;
  }
}

/** Открыт ли аварийный клапан — то есть ломятся ли сейчас со всех сторон. */
function клапанОткрыт(сейчас) {
  return неудачНаСейчас(общийСчёт, сейчас) >= НЕНОРМАЛЬНЫЙ_НАПОР;
}

/** Насколько притормозить попытку с этого счёта. */
function задержкаПоСчёту(счёт, сейчас) {
  const неудач = списатьЗабытое(счёт, сейчас);
  const прощаем = клапанОткрыт(сейчас) ? ПРОЩАЕМ_ПРИ_НАПОРЕ : ПРОЩАЕМ_НЕУДАЧ;
  if (неудач <= прощаем) return 0;

  const шагов = неудач - прощаем - 1;
  return Math.min(ПОТОЛОК_ЗАДЕРЖКИ, ПЕРВАЯ_ЗАДЕРЖКА * Math.pow(2, шагов));
}

/**
 * Общая пауза, которую при открытом клапане получает КАЖДАЯ попытка входа —
 * даже с адреса, за которым ничего не числится.
 *
 * Без неё перебор со сменой адресов не тормозило ничто: незнакомый адрес
 * проходил мгновенно, а адресов у любого мобильного оператора сотни.
 * Пауза растёт вдвое на каждый лишний «ненормальный напор» — чем шире
 * атака, тем дороже каждая попытка.
 */
function общаяПауза(сейчас) {
  const неудач = неудачНаСейчас(общийСчёт, сейчас);
  if (неудач < НЕНОРМАЛЬНЫЙ_НАПОР) return 0;

  const шагов = Math.floor(неудач / НЕНОРМАЛЬНЫЙ_НАПОР) - 1;
  return Math.min(ПОТОЛОК_ОБЩЕЙ_ПАУЗЫ, ОБЩАЯ_ПАУЗА * Math.pow(2, шагов));
}

function пауза(сколько) {
  return new Promise(function (дальше) { setTimeout(дальше, сколько); });
}

const ОТКАЗ_ОЧЕРЕДИ = {
  можно: false,
  причина: 'Слишком много попыток войти прямо сейчас. Подождите немного и попробуйте снова'
};

/**
 * Попроситься на попытку входа. Ответ приходит, когда выдержана пауза:
 * своя (за прошлые промахи этого адреса) или общая (при открытом клапане) —
 * что больше. За кем неудач не числится и пока клапан закрыт — проходит
 * сразу, записи в памяти ему не заводим.
 *
 * Отказываем, не разбирая кода, в двух случаях: с одного адреса уже ждут
 * слишком многие (перебор в несколько потоков) или пауз идёт слишком много
 * по всему серверу (перебор со сменой адресов). Отказ нам ничего не стоит
 * и кода не проверяет — значит, перебирателю от него нет никакой пользы.
 */
function пропустить(адрес) {
  const сейчас = Date.now();
  const счёт = поАдресам.get(ключАдреса(адрес));
  const своя = счёт ? задержкаПоСчёту(счёт, сейчас) : 0;
  const задержка = Math.max(своя, общаяПауза(сейчас));
  if (задержка <= 0) return Promise.resolve({ можно: true });

  if (счёт && счёт.ждут >= ПРЕДЕЛ_ОЧЕРЕДИ) return Promise.resolve(ОТКАЗ_ОЧЕРЕДИ);
  if (ждутСейчас >= ПРЕДЕЛ_ОЧЕРЕДИ_ВСЕГО) return Promise.resolve(ОТКАЗ_ОЧЕРЕДИ);

  if (счёт) счёт.ждут++;
  ждутСейчас++;
  return пауза(задержка).then(function () {
    if (счёт) счёт.ждут = Math.max(0, счёт.ждут - 1);
    ждутСейчас = Math.max(0, ждутСейчас - 1);
    return { можно: true };
  });
}

/** Код не подошёл — запоминаем неудачу за тем, кто её сделал. */
function записатьНеудачу(адрес) {
  const сейчас = Date.now();
  списатьЗабытое(общийСчёт, сейчас);
  // Общий счёт выше потолка не поднимаем: иначе после отбитой атаки клапан
  // остался бы открытым на часы, а платят за него в том числе честные игроки.
  общийСчёт.неудач = Math.min(ПОТОЛОК_ОБЩЕГО_СЧЁТА, общийСчёт.неудач + 1);

  const счёт = счётАдреса(адрес);
  списатьЗабытое(счёт, сейчас);
  счёт.неудач++;
}

/** Забыть все неудачи — нужно проверкам, чтобы начинать с чистого листа. */
function забытьВсё() {
  общийСчёт.неудач = 0;
  общийСчёт.когда = Date.now();
  поАдресам.clear();
}

/**
 * Что сейчас происходит — для проверок и для отладки.
 * Функция «просто посмотреть»: ничего не заводит и не меняет.
 * «Задержка сейчас» — самая большая пауза, которую шлагбаум держит прямо
 * сейчас: либо над самым провинившимся адресом, либо общая, если открыт
 * клапан. Тому, за кем неудач нет, при закрытом клапане достаётся ноль.
 */
function состояние() {
  const сейчас = Date.now();
  let худшая = общаяПауза(сейчас);
  const прощаем = клапанОткрыт(сейчас) ? ПРОЩАЕМ_ПРИ_НАПОРЕ : ПРОЩАЕМ_НЕУДАЧ;
  for (const счёт of поАдресам.values()) {
    const неудач = неудачНаСейчас(счёт, сейчас);
    if (неудач <= прощаем) continue;
    const задержка = Math.min(ПОТОЛОК_ЗАДЕРЖКИ,
      ПЕРВАЯ_ЗАДЕРЖКА * Math.pow(2, неудач - прощаем - 1));
    if (задержка > худшая) худшая = задержка;
  }

  return {
    неудачВсего: неудачНаСейчас(общийСчёт, сейчас),
    адресовПомним: поАдресам.size,
    вОчереди: ждутСейчас,
    задержкаСейчас: худшая,
    общаяПауза: общаяПауза(сейчас),
    клапанОткрыт: клапанОткрыт(сейчас)
  };
}

module.exports = {
  ПРОЩАЕМ_НЕУДАЧ: ПРОЩАЕМ_НЕУДАЧ,
  ПОТОЛОК_ЗАДЕРЖКИ: ПОТОЛОК_ЗАДЕРЖКИ,
  ПРЕДЕЛ_ОЧЕРЕДИ: ПРЕДЕЛ_ОЧЕРЕДИ,
  ПРЕДЕЛ_ОЧЕРЕДИ_ВСЕГО: ПРЕДЕЛ_ОЧЕРЕДИ_ВСЕГО,
  НЕНОРМАЛЬНЫЙ_НАПОР: НЕНОРМАЛЬНЫЙ_НАПОР,
  пропустить: пропустить,
  записатьНеудачу: записатьНеудачу,
  забытьВсё: забытьВсё,
  состояние: состояние
};
