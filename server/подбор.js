'use strict';

/* =====================================================================
   ПОДБОР СОПЕРНИКА: очередь ждущих для игры «Играть онлайн».

   Что это. Двое игроков с одинаковыми правилами (игра + число мест +
   переводной да/нет) встают на одну и ту же «полку» ожидания. Второй,
   кто встал, сразу сводится с первым. Ждать можно сколько угодно: бота
   очередь сама не подсаживает (решение владельца 30.09: «бота не сажать,
   только по кнопке»). Игрок, которому надоело ждать, просит бота сам —
   вызывающий код тогда забирает его запись через забратьДляБота и сам
   создаёт комнату с ботом.

   Чего здесь нет нарочно. Модуль НИЧЕГО не знает про HTTP и про
   server/комнаты.js — он только решает «кто с кем» и хранит очередь
   в памяти процесса. Создание комнаты, подпись Telegram, двери
   POST /подбор* — забота следующих этапов (Э2, Э3), не этого файла.

   Опознаватель записи — ключОжидания: случайная строка (48 hex-знаков
   из crypto.randomBytes), которую получает только сам вставший в
   очередь игрок. Чужим этот ключ не подделать на практике (энтропии
   достаточно), поэтому отдельной проверки «чей номер Telegram» у
   спроситьСтатус/отменить нет — ключ сам по себе и есть пропуск.
   ===================================================================== */

const crypto = require('crypto');

/* Запись, которую никто не спрашивает (ни встатьВОчередь тем же номером,
   ни статус, ни отменить) дольше этого срока, считается брошенной —
   вкладку закрыли, статус больше не придут спросить. 15 секунд — с
   запасом больше типичного интервала опроса клиента (несколько секунд),
   но не настолько долго, чтобы забытые записи копились надолго. */
const СРОК_БЕЗ_ОПРОСА_МС = 15000;

/* Потолок одновременных записей в очереди — защита от утечки памяти на
   случай, если штатная уборка по какой-то причине не успевает. Число
   с большим запасом над разумной одновременной нагрузкой одной игры. */
const ПОТОЛОК_ЗАПИСЕЙ = 500;

/** Map: ключ полки (игра+правила) -> список ждущих записей (по порядку). */
const полки = new Map();

/** Map: ключОжидания -> запись. Единая точка быстрого поиска по ключу. */
const поКлючу = new Map();

function теперь() {
  return Date.now();
}

/** Ключ полки собирается одной функцией, чтобы не разъезжались строки
 * ручной сборки в разных местах модуля. */
function ключПолки(игра, местВСтоле, переводной) {
  return String(игра) + '|мест' + String(местВСтоле) + '|переводной:' + (переводной ? 'да' : 'нет');
}

/* Состояние записи меняется ровно в этой функции (и нигде больше) — так
 * гонка «свели, и в тот же миг отменил» не может незаметно перезаписать
 * состояние в обход учёта: любой переход виден в одном месте. */
function сменитьСостояние(запись, новоеСостояние) {
  запись.состояние = новоеСостояние;
}

/** Убрать запись из очереди совсем — и из полки, и из поКлючу. */
function удалитьЗапись(запись) {
  поКлючу.delete(запись.ключОжидания);
  const список = полки.get(запись.ключПолки);
  if (!список) return;
  const очищенный = список.filter(function (з) { return з !== запись; });
  if (очищенный.length) полки.set(запись.ключПолки, очищенный);
  else полки.delete(запись.ключПолки);
}

/** Выкинуть записи, которые никто не спрашивал дольше СРОК_БЕЗ_ОПРОСА_МС. */
function уборкаЗависших() {
  const сейчас = теперь();
  const зависшие = [];
  поКлючу.forEach(function (запись) {
    if (сейчас - запись.спрошенВ > СРОК_БЕЗ_ОПРОСА_МС) зависшие.push(запись);
  });
  зависшие.forEach(удалитьЗапись);
}

/** При превышении потолка — выкинуть самую старую запись, чтобы дать
 * место новой (это не должно случаться в норме, только при сбое уборки). */
function освободитьМестоПриПереполнении() {
  if (поКлючу.size < ПОТОЛОК_ЗАПИСЕЙ) return;
  let самаяСтарая = null;
  поКлючу.forEach(function (запись) {
    if (!самаяСтарая || запись.всталВ < самаяСтарая.всталВ) самаяСтарая = запись;
  });
  if (самаяСтарая) удалитьЗапись(самаяСтарая);
}

function новаяЗапись(номерТелеграм, имя, метка, игра, полка) {
  const сейчас = теперь();
  return {
    номерТелеграм: номерТелеграм,
    имя: имя,
    метка: метка,
    игра: игра,
    ключПолки: полка,
    ключОжидания: crypto.randomBytes(24).toString('hex'),
    всталВ: сейчас,
    спрошенВ: сейчас,
    состояние: 'ждёт',
    сКем: null
  };
}

/** Публичный вид записи для ответа встатьВОчередь. */
function видДляВставшего(запись) {
  if (запись.состояние === 'свели') {
    return { статус: 'свели', ключОжидания: запись.ключОжидания, сКем: запись.сКем };
  }
  return { статус: 'ждёт', ключОжидания: запись.ключОжидания };
}

/**
 * Встать в очередь ожидания соперника.
 * параметры: { номерТелеграм, имя, метка, игра, местВСтоле, переводной }.
 * Возвращает либо { статус: 'свели', ключОжидания, сКем } — партнёр уже
 * нашёлся, либо { статус: 'ждёт', ключОжидания } — встал, жди.
 */
function встатьВОчередь(параметры) {
  параметры = параметры || {};
  const номерТелеграм = параметры.номерТелеграм;
  if (!номерТелеграм) throw new TypeError('встатьВОчередь: нужен номерТелеграм');
  const имя = параметры.имя || '';
  const метка = параметры.метка || '';
  const игра = параметры.игра || 'дурак';
  const местВСтоле = параметры.местВСтоле || 2;
  const переводной = !!параметры.переводной;

  уборкаЗависших();

  const полка = ключПолки(игра, местВСтоле, переводной);
  const список = полки.get(полка) || [];

  /* Один номер Telegram — одна запись на этой полке: если этот номер уже
   * стоит (ждёт или только что свели, но результат ещё не забрали) —
   * возвращаем ту же запись, вторую не заводим. */
  let своя = список.find(function (з) { return з.номерТелеграм === номерТелеграм; });
  if (!своя) {
    поКлючу.forEach(function (з) {
      if (своя) return;
      if (з.номерТелеграм === номерТелеграм && з.ключПолки === полка && з.состояние !== 'отменён') {
        своя = з;
      }
    });
  }
  if (своя) {
    своя.спрошенВ = теперь();
    return видДляВставшего(своя);
  }

  /* Партнёр — самый первый из ждущих на этой полке. */
  const партнёр = список.find(function (з) { return з.состояние === 'ждёт'; });

  const запись = новаяЗапись(номерТелеграм, имя, метка, игра, полка);

  if (партнёр) {
    /* Метка страницы партнёра нужна серверу, чтобы запомнить посадку
       обоим (повтор после потерянного ответа отдаст то же место). Наружу
       сКем не уходит — ответы игроку сервер собирает поле за полем. */
    сменитьСостояние(партнёр, 'свели');
    партнёр.сКем = { номерТелеграм: запись.номерТелеграм, имя: запись.имя, метка: запись.метка };
    партнёр.спрошенВ = теперь();

    сменитьСостояние(запись, 'свели');
    запись.сКем = { номерТелеграм: партнёр.номерТелеграм, имя: партнёр.имя, метка: партнёр.метка };

    /* Обоих убираем из списка ожидания полки — партнёр там был, запись
     * туда так и не попадала. поКлючу хранит обоих: по ним ещё спросят
     * статус. */
    полки.set(полка, список.filter(function (з) { return з !== партнёр; }));
    поКлючу.set(запись.ключОжидания, запись);
    return видДляВставшего(запись);
  }

  освободитьМестоПриПереполнении();
  список.push(запись);
  полки.set(полка, список);
  поКлючу.set(запись.ключОжидания, запись);
  return видДляВставшего(запись);
}

/**
 * Статус по ключу ожидания. Возвращает один из:
 *   { статус: 'ждёт' }
 *   { статус: 'свели', сКем }
 *   { статус: 'не_найдено' }  — ключ чужой, устарел или отменён.
 */
function статус(ключОжидания) {
  уборкаЗависших();
  const запись = поКлючу.get(ключОжидания);
  if (!запись || запись.состояние === 'отменён') {
    return { статус: 'не_найдено' };
  }
  запись.спрошенВ = теперь();

  if (запись.состояние === 'свели') {
    return { статус: 'свели', сКем: запись.сКем };
  }

  return { статус: 'ждёт' };
}

/**
 * Отменить ожидание по ключу. Возвращает { ок: true }, если запись была
 * и её убрали, { ок: false } — ключ уже не найден (чужой/устарел/уже
 * отменён раньше).
 */
function отменить(ключОжидания) {
  уборкаЗависших();
  const запись = поКлючу.get(ключОжидания);
  if (!запись || запись.состояние === 'отменён') {
    return { ок: false };
  }
  сменитьСостояние(запись, 'отменён');
  удалитьЗапись(запись);
  return { ок: true };
}

/**
 * Игрок сам попросил бота («Играть с ботом»): забрать его запись из
 * очереди. Возвращает { ок: true } только для того, кто ещё ЖДЁТ: уже
 * сведённого с человеком (пару пообещали двоим), отменённого и чужого
 * ключа забрать нельзя — { ок: false }. Запись убирается тут же, в одном
 * синхронном ходу, поэтому повторный вызов с тем же ключом получит отказ
 * и второй комнаты с ботом не будет.
 */
function забратьДляБота(ключОжидания) {
  уборкаЗависших();
  const запись = поКлючу.get(ключОжидания);
  if (!запись || запись.состояние !== 'ждёт') return { ок: false };
  сменитьСостояние(запись, 'отменён');
  удалитьЗапись(запись);
  return { ок: true };
}

/**
 * Запись по ключу, которую уже свели с человеком, — или null (ждёт,
 * отменена, чужой или устаревший ключ). Нужна двери «Играть с ботом»:
 * кнопку нажали в тот же миг, когда очередь свела пару, — игроку надо
 * отдать его место в этой паре, а не отказ. Возвращает только то, по
 * чему сервер найдёт это место и сверит владельца: номер Telegram
 * владельца ключа, игру, метку страницы и партнёра.
 */
function сведённаяЗапись(ключОжидания) {
  уборкаЗависших();
  const запись = поКлючу.get(ключОжидания);
  if (!запись || запись.состояние !== 'свели') return null;
  запись.спрошенВ = теперь();
  return {
    номерТелеграм: запись.номерТелеграм,
    игра: запись.игра,
    метка: запись.метка,
    сКем: запись.сКем
  };
}

module.exports = {
  встатьВОчередь: встатьВОчередь,
  статус: статус,
  отменить: отменить,
  забратьДляБота: забратьДляБота,
  сведённаяЗапись: сведённаяЗапись
};
