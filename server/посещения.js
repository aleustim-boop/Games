'use strict';

/* =====================================================================
   Посещения игры: кто сейчас в игре, кто заходил сегодня и за неделю.
   Задание: штаб/план-онлайн-дашборд.md, разделы «Главное» и «Этап 1».

   Откуда данные. Браузер шлёт короткий пульс (POST /пульс) при открытии
   страницы и раз в 60 с, пока вкладка видна (это добавит сервер на
   этапе 2). Здесь — только счётная часть: из пульсов складываются
   СЕССИИ, из сессий — сводка для дашборда владельца.

   Сессия — это { номер, имя, начало, конец, играСейчас, минутыПоИграм }:
     номер          строка из цифр (id игрока в Telegram)
     имя            подпись из Telegram, обрезанная до 40 знаков
     начало, конец  время в миллисекундах (Date.now())
     играСейчас     какая игра была в последнем пульсе сессии
     минутыПоИграм  {дурак: 2, шашки: 0.5, …} — сколько минут набежало
                    в каждой игре внутри этой сессии

   ПРАВИЛО ПАУЗЫ. Пока пульсы от одного номера идут с паузой не больше
   ПАУЗА_НОВАЯ_СЕССИЯ_МС (3 мин) — это одна сессия, и очередной пульс
   добавляет к минутыПоИграм[игра] время, прошедшее с предыдущего пульса.
   Пауза больше — старая сессия закрыта, начинается новая; время самой
   паузы никуда не засчитывается (человека за игрой не было).

   ПРАВИЛО ЧАСТОТЫ. Пульс, пришедший от того же номера меньше чем через
   ПУЛЬС_МИН_ИНТЕРВАЛ_МС (30 с) после предыдущего ПРИНЯТОГО пульса —
   отбрасывается целиком: не продлевает сессию и не считается минутой.
   Так двойная отправка (например, вкладка открылась дважды) не рисует
   лишнее время.

   ПОЧЕМУ «КОНЕЦ = ПОСЛЕДНИЙ ПУЛЬС + 1 МИНУТА». Пульс говорит «человек
   был здесь только что», а не «человек ушёл прямо сейчас» — до
   следующего пульса, которого могло и не случиться, пройдёт ещё меньше
   минуты. Поэтому в поле «конец» сессии (то, что видно как «последний
   раз») закладывается запас в ХВОСТ_ПОСЛЕ_ПУЛЬСА_МС (1 мин). Этот запас
   — только для отметки времени; счётчик минутыПоИграм копится исключительно
   по фактическим промежуткам между пульсами и его не трогает (иначе
   любая, даже мгновенная сессия дорисовывала бы себе лишнюю минуту).
   Проверено на 3 пульсах подряд с шагом 60 с: минутыПоИграм = 2 (две
   пройденные минуты между тремя отметками), а не 3.

   «СЕЙЧАС» — те, у кого последний пульс не старше ПАУЗА_НОВАЯ_СЕССИЯ_МС
   (тот же порог в 3 мин, что и для новой сессии: не ответил вкладкой —
   значит, скорее всего, закрыл её или свернул телефон).

   Файл на диске — как server/статистика.js: пишется отложенно, во
   временный файл «.пишем» с переименованием поверх настоящего, чтобы
   обрыв записи не оставил половинку. Путь и часы — доводы ФАБРИКИ
   создать(), а не фиксированные значения: серверу нужен настоящий путь
   и настоящее время, а проверке — своя временная папка и подставные
   часы, которые можно двигать вручную. Общий путь по умолчанию (когда
   доводов нет) берётся из server/папка-данных.js — так же, как в
   статистика.js.
   ===================================================================== */

const fs = require('fs');
const path = require('path');

const гдеДанные = require('./папка-данных.js');

/* Игры берём из общего реестра браузера — так же, как сервер берёт правила.
   Раньше тут стоял список из 4 игр, и пульсы монополии, катана, покера и
   головоломок молча отбрасывались. */
const реестрИгр = require('../общее/js/игры-реестр.js');
const ИГРЫ = реестрИгр.все().map(function (запись) { return запись.ключ; });

/* Гость — человек из обычного браузера без Telegram. Его ид — случайная
   строка из 16–32 латинских букв и цифр, которую страница хранит у себя. */
const ГОСТЬ_ИД_ШАБЛОН = /^[a-z0-9]{16,32}$/;
const НОВЫХ_ГОСТЕЙ_В_СУТКИ_МАКС = 2000;      // защита от накрутки: больше новых ид за сутки не принимаем

const ИМЯ_МАКС = 40;                        // длиннее подпись Telegram не бывает нужна
const ПАУЗА_НОВАЯ_СЕССИЯ_МС = 3 * 60 * 1000; // тишина дольше — новая сессия, и порог «сейчас»
const ПУЛЬС_МИН_ИНТЕРВАЛ_МС = 30 * 1000;     // чаще — пульс отбрасывается
const ХВОСТ_ПОСЛЕ_ПУЛЬСА_МС = 60 * 1000;     // запас в «конец»: последний пульс + 1 мин
const ХРАНИМ_ДНЕЙ = 30;
const СЕССИЙ_НА_НОМЕР_В_ДЕНЬ_МАКС = 200;
const ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ = 5000;             // как в статистика.js — не бить по диску на каждый пульс

/** «2026-09-23» по местному времени машины — тем же приёмом, что в статистика.js. */
function ключДня(время) {
  const дата = new Date(время);
  const месяц = String(дата.getMonth() + 1).padStart(2, '0');
  const число = String(дата.getDate()).padStart(2, '0');
  return дата.getFullYear() + '-' + месяц + '-' + число;
}

/** Ключ дня, отстоящего на столько-то дней назад от указанного момента. */
function ключДняНазад(отКакогоМс, сколькоНазад) {
  const дата = new Date(отКакогоМс);
  дата.setDate(дата.getDate() - сколькоНазад);
  return ключДня(дата.getTime());
}

/** Номер принимается, только если после обрезки пробелов он целиком из цифр. */
function очиститьНомер(вход) {
  const строка = String(вход === undefined || вход === null ? '' : вход).trim();
  // Раньше "a9b0b0" обрезался до цифр "900" и молча принимался — мусор
  // вокруг цифр проходил. Теперь номер годится, только если он ЦЕЛИКОМ
  // состоит из цифр (1-20 знаков — с запасом под id Telegram).
  return /^\d{1,20}$/.test(строка) ? строка : '';
}

/** Ид гостя годится, только если он целиком из 16–32 латинских букв и цифр. */
function очиститьИдГостя(вход) {
  const строка = typeof вход === 'string' ? вход : '';
  return ГОСТЬ_ИД_ШАБЛОН.test(строка) ? строка : '';
}

/** Имя — строкой без управляющих знаков, не длиннее ИМЯ_МАКС знаков. */
function очиститьИмя(вход) {
  const строка = typeof вход === 'string' ? вход : '';
  // Управляющие знаки (\n, \x00 и т.п.) вырезаем ДО обрезки длины — иначе
  // длинное имя с мусором в начале обрезалось бы до одного мусора.
  return строка.replace(/[\x00-\x1F\x7F]/g, '').slice(0, ИМЯ_МАКС);
}

/**
 * Создать отдельный экземпляр учёта посещений.
 * @param {{файл?: string, часы?: Function}} настройки
 *   файл  — путь к файлу на диске; 'без диска' или отсутствие файла при
 *           отсутствии всей настройки → берём server/папка-данных.js
 *           (боевой путь); явное 'без диска' — совсем без записи (для
 *           проверок, которым диск не нужен).
 *   часы  — () => мс «сейчас»; без довода — настоящий Date.now. Учесть()
 *           и сводка() всё равно принимают «сейчас» явным доводом —
 *           часы нужны как запасной вариант, если его не передали.
 */
function создать(настройки) {
  настройки = настройки || {};
  const часы = typeof настройки.часы === 'function' ? настройки.часы : Date.now;

  let путьКФайлу;
  if (настройки.файл === 'без диска') путьКФайлу = null;
  else if (typeof настройки.файл === 'string' && настройки.файл) путьКФайлу = настройки.файл;
  else путьКФайлу = гдеДанные.файл('посещения.json');

  const файлПокаПишем = путьКФайлу ? путьКФайлу + '.пишем' : null;

  /* номер (строка) → массив сессий, по возрастанию времени начала. */
  const сессииПоНомерам = new Map();
  /* номер (строка) → мс последнего ПРИНЯТОГО пульса — для правила частоты. */
  const последнийПринятыйПульс = new Map();
  /* Гости — свои две карты, чтобы они никогда не попали в списки людей:
     ид гостя → сессии, ид гостя → мс последнего принятого пульса. */
  const сессииГостей = new Map();
  const последнийПульсГостя = new Map();

  let ужеЗагрузили = путьКФайлу === null; // без диска грузить нечего — считаем «уже».
  let естьЧтоЗаписать = false;
  let таймерЗаписи = null;

  /** Все сессии подряд — для сохранения на диск и для обхода в сводке. */
  function всеСессии() {
    const итог = [];
    for (const список of сессииПоНомерам.values()) {
      for (const сессия of список) итог.push(сессия);
    }
    return итог;
  }

  /** Прочитать память с диска. Файла нет или он испорчен — начинаем с пустого. */
  function загрузить() {
    ужеЗагрузили = true;
    if (!путьКФайлу) return;
    let текст = '';
    try {
      текст = fs.readFileSync(путьКФайлу, 'utf8');
    } catch (сбой) {
      return; // файла нет — так и должно быть при первом запуске
    }
    let прочитанное = null;
    try {
      прочитанное = JSON.parse(текст);
    } catch (сбой) {
      return; // испорчен — молча начинаем с чистого листа
    }
    if (!прочитанное || !Array.isArray(прочитанное.сессии)) return;

    // Старый файл без поля «гости» грузится как раньше — гостей просто нет.
    разобратьСессии(прочитанное.сессии, очиститьНомер, сессииПоНомерам, последнийПринятыйПульс, true);
    if (Array.isArray(прочитанное.гости)) {
      разобратьСессии(прочитанное.гости, очиститьИдГостя, сессииГостей, последнийПульсГостя, false);
    }
    прибраться(часы());
  }

  /** Разложить записи с диска по карте: общий разбор для людей и гостей. */
  function разобратьСессии(записи, очиститьИд, карта, картаПульсов, сИменами) {
    for (const запись of записи) {
      if (!запись || typeof запись !== 'object') continue;
      const номер = очиститьИд(запись.номер);
      if (!номер) continue;
      const начало = Number(запись.начало);
      const конец = Number(запись.конец);
      if (!Number.isFinite(начало) || !Number.isFinite(конец)) continue;
      const минутыПоИграм = {};
      if (запись.минутыПоИграм && typeof запись.минутыПоИграм === 'object') {
        for (const игра of ИГРЫ) {
          const число = Number(запись.минутыПоИграм[игра]);
          if (Number.isFinite(число) && число > 0) минутыПоИграм[игра] = число;
        }
      }
      const сессия = {
        номер: номер,
        имя: сИменами ? очиститьИмя(запись.имя) : '',
        начало: начало,
        конец: конец,
        последнийПульс: конец - ХВОСТ_ПОСЛЕ_ПУЛЬСА_МС,
        играСейчас: ИГРЫ.indexOf(запись.играСейчас) !== -1 ? запись.играСейчас : ИГРЫ[0],
        минутыПоИграм: минутыПоИграм
      };
      if (!карта.has(номер)) карта.set(номер, []);
      карта.get(номер).push(сессия);
    }
    // Порядок по начало — на случай, если в файле он был другим.
    for (const список of карта.values()) список.sort((a, b) => a.начало - b.начало);
    // Правило частоты восстанавливаем по самому свежему пульсу каждого номера.
    for (const [номер, список] of карта) {
      const последняя = список[список.length - 1];
      картаПульсов.set(номер, последняя.последнийПульс);
    }
  }

  function убедитьсяЧтоЗагружено() {
    if (!ужеЗагрузили) загрузить();
  }

  /** Сложить память в файл. Молча: беда с диском не повод ронять сервер. */
  function записатьСейчас() {
    естьЧтоЗаписать = false;
    if (!путьКФайлу) return;
    const список = всеСессии().map(function (с) {
      return {
        номер: с.номер, имя: с.имя, начало: с.начало, конец: с.конец,
        играСейчас: с.играСейчас, минутыПоИграм: с.минутыПоИграм
      };
    });
    const гости = [];
    for (const сессии of сессииГостей.values()) {
      for (const с of сессии) {
        гости.push({ номер: с.номер, начало: с.начало, конец: с.конец, играСейчас: с.играСейчас, минутыПоИграм: с.минутыПоИграм });
      }
    }
    try {
      fs.mkdirSync(path.dirname(путьКФайлу), { recursive: true });
      fs.writeFileSync(файлПокаПишем, JSON.stringify({ сессии: список, гости: гости }), 'utf8');
      fs.renameSync(файлПокаПишем, путьКФайлу);
    } catch (сбой) {
      /* Не записалось — попробуем при следующем изменении. */
    }
  }

  function записатьПогодя() {
    if (!путьКФайлу) return;
    естьЧтоЗаписать = true;
    if (таймерЗаписи !== null) return;
    таймерЗаписи = setTimeout(function () {
      таймерЗаписи = null;
      if (естьЧтоЗаписать) записатьСейчас();
    }, ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ);
    if (таймерЗаписи.unref) таймерЗаписи.unref();
  }

  /** Записать прямо сейчас, если было что (нужно при остановке сервера и в проверках). */
  function дописать() {
    if (таймерЗаписи !== null) {
      clearTimeout(таймерЗаписи);
      таймерЗаписи = null;
    }
    if (естьЧтоЗаписать) записатьСейчас();
  }

  /** Выбросить сессии старше срока хранения, относительно момента сейчасМс. */
  function прибраться(сейчасМс) {
    const самыйСтарый = ключДняНазад(сейчасМс, ХРАНИМ_ДНЕЙ - 1);
    прибратьКарту(сессииПоНомерам, последнийПринятыйПульс, самыйСтарый);
    прибратьКарту(сессииГостей, последнийПульсГостя, самыйСтарый);
  }

  function прибратьКарту(карта, картаПульсов, самыйСтарый) {
    for (const [номер, список] of карта) {
      const свежие = список.filter(function (с) { return ключДня(с.начало) >= самыйСтарый; });
      if (свежие.length === 0) {
        // Ни одной сессии не осталось — само правило частоты для этого
        // номера тоже больше не нужно, иначе карта растёт без предела.
        карта.delete(номер);
        картаПульсов.delete(номер);
      } else if (свежие.length !== список.length) {
        карта.set(номер, свежие);
      }
    }
  }

  /** Для проверок: сколько номеров сейчас держит правило частоты пульса в памяти. */
  function размерПульсов() {
    return последнийПринятыйПульс.size;
  }

  /**
   * Пульс от игрока. Возвращает true, если он принят и что-то изменил,
   * false — если отброшен (кривые данные, частый повтор, лимит сессий).
   */
  function учесть(номерВх, имяВх, играВх, сейчасВх) {
    убедитьсяЧтоЗагружено();
    const номер = очиститьНомер(номерВх);
    if (!номер) return false;                        // кривой номер
    if (ИГРЫ.indexOf(играВх) === -1) return false;    // чужая игра
    const имя = очиститьИмя(имяВх);
    const сейчасМс = typeof сейчасВх === 'number' && Number.isFinite(сейчасВх) ? сейчасВх : часы();
    return принять(сессииПоНомерам, последнийПринятыйПульс, номер, имя, играВх, сейчасМс, false);
  }

  /**
   * Пульс гостя (человек без Telegram). Те же правила паузы и частоты, что
   * у людей, но своя карта: в списки людей гость не попадает, имён у него
   * нет. Новых гостей — не больше НОВЫХ_ГОСТЕЙ_В_СУТКИ_МАКС в сутки.
   */
  function учестьГостя(идВх, играВх, сейчасВх) {
    убедитьсяЧтоЗагружено();
    const ид = очиститьИдГостя(идВх);
    if (!ид) return false;                           // кривой ид
    if (ИГРЫ.indexOf(играВх) === -1) return false;    // чужая игра
    const сейчасМс = typeof сейчасВх === 'number' && Number.isFinite(сейчасВх) ? сейчасВх : часы();
    return принять(сессииГостей, последнийПульсГостя, ид, '', играВх, сейчасМс, true);
  }

  /** Сколько разных гостей впервые пришли в указанный день (ключ дня). */
  function новыхГостейЗаДень(день) {
    let число = 0;
    for (const список of сессииГостей.values()) {
      if (ключДня(список[0].начало) === день) число++;
    }
    return число;
  }

  /** Общая часть пульса человека и гостя; карты у них разные. */
  function принять(карта, картаПульсов, номер, имя, играВх, сейчасМс, этоГость) {
    const последний = картаПульсов.get(номер);
    if (последний !== undefined && сейчасМс - последний < ПУЛЬС_МИН_ИНТЕРВАЛ_МС) {
      return false;                                   // слишком частый пульс — отброшен
    }

    const список = карта.get(номер) || [];
    const последняя = список.length > 0 ? список[список.length - 1] : null;

    if (последняя && сейчасМс - последняя.последнийПульс <= ПАУЗА_НОВАЯ_СЕССИЯ_МС) {
      // Продолжение той же сессии: минуты копим по фактической разнице
      // пульсов. Math.max(0, …) — на случай, если часы дёрнутся назад:
      // отрицательных минут быть не должно.
      const дельтаМин = Math.max(0, (сейчасМс - последняя.последнийПульс) / 60000);
      // Время между пульсами относится к игре, в которой человек БЫЛ до
      // этого пульса (играСейчас предыдущей записи), а не к новой игре —
      // иначе при переключении игры внутри сессии минуты задним числом
      // уезжали бы не в ту игру.
      const играДоПульса = последняя.играСейчас;
      последняя.минутыПоИграм[играДоПульса] = (последняя.минутыПоИграм[играДоПульса] || 0) + дельтаМин;
      последняя.последнийПульс = сейчасМс;
      последняя.конец = сейчасМс + ХВОСТ_ПОСЛЕ_ПУЛЬСА_МС;
      последняя.играСейчас = играВх;
      последняя.имя = имя;
    } else {
      // Новая сессия — если не упёрлись в дневной лимит для этого номера.
      const сегодня = ключДня(сейчасМс);
      const сессийСегодня = список.filter(function (с) { return ключДня(с.начало) === сегодня; }).length;
      if (сессийСегодня >= СЕССИЙ_НА_НОМЕР_В_ДЕНЬ_МАКС) return false;
      // Совсем новый гость — смотрим суточный потолок, чтобы накруткой
      // нельзя было раздуть память и числа посещений.
      if (этоГость && список.length === 0 && новыхГостейЗаДень(сегодня) >= НОВЫХ_ГОСТЕЙ_В_СУТКИ_МАКС) return false;

      const новая = {
        номер: номер, имя: имя,
        начало: сейчасМс, последнийПульс: сейчасМс, конец: сейчасМс + ХВОСТ_ПОСЛЕ_ПУЛЬСА_МС,
        играСейчас: играВх, минутыПоИграм: {}
      };
      список.push(новая);
      карта.set(номер, список);
    }

    картаПульсов.set(номер, сейчасМс);
    прибраться(сейчасМс);
    записатьПогодя();
    return true;
  }

  /** Сумма всех минутыПоИграм сессии — целое число минут. */
  function минутСессии(с) {
    let сумма = 0;
    for (const игра of ИГРЫ) сумма += с.минутыПоИграм[игра] || 0;
    return сумма;
  }

  /** Сложить минутыПоИграм нескольких сессий в один объект — только игры с ненулевым временем. */
  function сложитьМинутыПоИграм(сессии) {
    const итог = {};
    for (const с of сессии) {
      for (const игра of ИГРЫ) {
        const число = с.минутыПоИграм[игра] || 0;
        if (число > 0) итог[игра] = (итог[игра] || 0) + число;
      }
    }
    for (const игра of Object.keys(итог)) итог[игра] = Math.round(итог[игра]);
    return итог;
  }

  /** Список людей по сессиям, начавшимся не раньше самыйСтарый (ключ дня), отсортированный по убыванию минут. */
  function людиЗаПериод(самыйСтарый) {
    const итог = [];
    for (const [номер, список] of сессииПоНомерам) {
      const вПериоде = список.filter(function (с) { return ключДня(с.начало) >= самыйСтарый; });
      if (вПериоде.length === 0) continue;
      const самаяСвежая = вПериоде.reduce(function (a, b) { return b.начало > a.начало ? b : a; });
      const суммаМинут = вПериоде.reduce(function (сумма, с) { return сумма + минутСессии(с); }, 0);
      const последнийРаз = Math.max.apply(null, вПериоде.map(function (с) { return с.конец; }));
      итог.push({
        номер: номер,
        имя: самаяСвежая.имя,
        заходов: вПериоде.length,
        минут: Math.round(суммаМинут),
        минутыПоИграм: сложитьМинутыПоИграм(вПериоде),
        последнийРаз: последнийРаз
      });
    }
    итог.sort(function (a, b) { return b.минут - a.минут; });
    return итог;
  }

  /**
   * Сводка на момент «сейчас»: кто в игре прямо сейчас, кто заходил
   * сегодня и кто заходил за последние 7 дней (включая сегодня).
   */
  function сводка(сейчасВх) {
    убедитьсяЧтоЗагружено();
    const сейчасМс = typeof сейчасВх === 'number' && Number.isFinite(сейчасВх) ? сейчасВх : часы();
    прибраться(сейчасМс);

    const сейчасСписок = [];
    for (const [номер, список] of сессииПоНомерам) {
      const последняя = список[список.length - 1];
      if (сейчасМс - последняя.последнийПульс <= ПАУЗА_НОВАЯ_СЕССИЯ_МС) {
        сейчасСписок.push({
          номер: номер, имя: последняя.имя, игра: последняя.играСейчас,
          минут: Math.round((сейчасМс - последняя.начало) / 60000)
        });
      }
    }
    сейчасСписок.sort(function (a, b) { return b.минут - a.минут; });

    let гостейСейчас = 0;
    for (const список of сессииГостей.values()) {
      if (сейчасМс - список[список.length - 1].последнийПульс <= ПАУЗА_НОВАЯ_СЕССИЯ_МС) гостейСейчас++;
    }

    return {
      сейчас: сейчасСписок,
      сегодня: людиЗаПериод(ключДня(сейчасМс)),
      неделя: людиЗаПериод(ключДняНазад(сейчасМс, 6)),
      // Гости — только числа, без списка и без ид.
      гости: {
        сейчас: гостейСейчас,
        сегодня: числаГостей(ключДня(сейчасМс)),
        неделя: числаГостей(ключДняНазад(сейчасМс, 6))
      }
    };
  }

  /** Все сессии карты, начавшиеся не раньше самыйСтарый (ключ дня). */
  function сессииЗаПериод(карта, самыйСтарый) {
    const итог = [];
    for (const список of карта.values()) {
      for (const с of список) if (ключДня(с.начало) >= самыйСтарый) итог.push(с);
    }
    return итог;
  }

  /** Числа по гостям за период: сколько разных, заходов, минут, минуты по играм. */
  function числаГостей(самыйСтарый) {
    const сессии = сессииЗаПериод(сессииГостей, самыйСтарый);
    const разных = new Set(сессии.map(function (с) { return с.номер; }));
    return {
      гостей: разных.size,
      заходов: сессии.length,
      минут: Math.round(сессии.reduce(function (сумма, с) { return сумма + минутСессии(с); }, 0)),
      минутыПоИграм: сложитьМинутыПоИграм(сессии)
    };
  }

  /**
   * Числа для /статистика за последние дни (1 — сегодня, 7, 30), только
   * числа: людей из Telegram, гостей, минуты по играм (отдельно людей и гостей).
   */
  function числаЗаДни(дней, сейчасВх) {
    убедитьсяЧтоЗагружено();
    const сейчасМс = typeof сейчасВх === 'number' && Number.isFinite(сейчасВх) ? сейчасВх : часы();
    прибраться(сейчасМс);
    const сколько = Math.min(ХРАНИМ_ДНЕЙ, Math.max(1, Math.floor(Number(дней)) || 1));
    const самыйСтарый = ключДняНазад(сейчасМс, сколько - 1);
    const людиСессии = сессииЗаПериод(сессииПоНомерам, самыйСтарый);
    const гостиСессии = сессииЗаПериод(сессииГостей, самыйСтарый);
    const людиМинуты = сложитьМинутыПоИграм(людиСессии);
    const гостиМинуты = сложитьМинутыПоИграм(гостиСессии);
    const минутыПоИграм = {};
    for (const игра of ИГРЫ) {
      const л = людиМинуты[игра] || 0;
      const г = гостиМинуты[игра] || 0;
      if (л > 0 || г > 0) минутыПоИграм[игра] = { люди: л, гости: г };
    }
    return {
      дней: сколько,
      людей: new Set(людиСессии.map(function (с) { return с.номер; })).size,
      гостей: new Set(гостиСессии.map(function (с) { return с.номер; })).size,
      минутыПоИграм: минутыПоИграм
    };
  }

  /**
   * Когда каждый человек был в игре в последний раз: [{ номер, последнийРаз }],
   * где последнийРаз — самый поздний «конец» его сессий (пульс + 1 мин).
   * Гостей здесь нет: писать им некуда. Нужно письмам «давно не заходили».
   */
  function последниеЗаходы(сейчасВх) {
    убедитьсяЧтоЗагружено();
    const сейчасМс = typeof сейчасВх === 'number' && Number.isFinite(сейчасВх) ? сейчасВх : часы();
    прибраться(сейчасМс);
    const итог = [];
    for (const [номер, список] of сессииПоНомерам) {
      const последнийРаз = Math.max.apply(null, список.map(function (с) { return с.конец; }));
      итог.push({ номер: номер, последнийРаз: последнийРаз });
    }
    return итог;
  }

  return {
    учесть: учесть,
    последниеЗаходы: последниеЗаходы,
    учестьГостя: учестьГостя,
    числаЗаДни: числаЗаДни,
    сводка: сводка,
    дописать: дописать,
    размерПульсов: размерПульсов // только для проверок: карта правила частоты не растёт бесконечно
  };
}

