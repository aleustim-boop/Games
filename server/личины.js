function вариантыЗеркала(текст) {
  if (ЗЕРКАЛО[текст]) return ЗЕРКАЛО[текст];
  if (ТЕКСТЫ_РЕАКЦИЙ.indexOf(текст) !== -1) return [текст];   // остальные смайлики — тем же
  return null;
}

/**
 * Что личина «скажет» по поводу, и через сколько. Возвращает
 * { текст, черезМс } или null (промолчит).
 *   повод — строка 'сел' | 'победа' | 'поражение' | 'ожидание' или
 *           объект { вид: 'знак', текст: 'текст знака человека' };
 *   состояние — объект личины за столом: { сила, последняя, сейчас }.
 *           Сюда же пишем время последней реакции для кулдауна (20 с);
 *           «сейчас» — необязательные часы (по умолчанию Date.now());
 *   случай — генератор 0..1 (по умолчанию Math.random).
 * Номер знака в каталоге игры ищет вызывающий по тексту.
 */
function реакция(повод, состояние, случай) {
  const жребий = typeof случай === 'function' ? случай : Math.random;
  const вид = повод && typeof повод === 'object' ? повод.вид : повод;
  const правило = ПОВОДЫ[вид];
  if (!правило || !состояние || typeof состояние !== 'object') return null;

  const сейчас = Number.isFinite(состояние.сейчас) ? состояние.сейчас : Date.now();
  if (Number.isFinite(состояние.последняя) && сейчас - состояние.последняя < КУЛДАУН_РЕАКЦИИ_МС) return null;
  if (жребий() >= правило.шанс) return null;

  let варианты;
  if (вид === 'знак') {
    варианты = вариантыЗеркала(повод && повод.текст);
  } else {
    const поСиле = ЛЮБИМЫЕ[вид];
    варианты = поСиле[состояние.сила] || поСиле['средний'];
  }
  if (!варианты || варианты.length === 0) return null;

  const черезМс = Math.round(правило.отМс + жребий() * (правило.доМс - правило.отМс));
  const текст = варианты[Math.min(варианты.length - 1, Math.floor(жребий() * варианты.length))];
  состояние.последняя = сейчас;
  return { текст: текст, черезМс: черезМс };
}

/* ---------------------------------------------------------------------
   Фото личины — файл из img/личины/. Читаем один раз и держим в памяти.
   --------------------------------------------------------------------- */
const кэшФото = new Map();

function типФото(имяФайла) {
  if (/\.svg$/i.test(имяФайла)) return 'image/svg+xml';
  if (/\.png$/i.test(имяФайла)) return 'image/png';
  if (/\.webp$/i.test(имяФайла)) return 'image/webp';
  return 'image/jpeg';
}

/** Байты фото личины { байты, тип } или null (у личины нет фото / файла нет). */
function фото(номер) {
  const личина = личинаПоНомеру(номер);
  if (!личина || !личина.фото) return null;
  if (кэшФото.has(личина.фото)) return кэшФото.get(личина.фото);
  try {
    const результат = { байты: fs.readFileSync(path.join(ПАПКА_ФОТО, личина.фото)), тип: типФото(личина.фото) };
    кэшФото.set(личина.фото, результат);
    return результат;
  } catch (сбой) {
    // Файла нет (ещё рисуется или потерян) — тихо отдаём «нет фото» и
    // НЕ запоминаем это: когда файл появится, он подхватится без перезапуска.
    return null;
  }
}

/** Есть ли у личины фото (файл на месте). */
function естьФото(номер) {
  return фото(номер) !== null;
}

