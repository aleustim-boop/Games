/**
 * Выбрать личину для нового стола: не сидящую сейчас ни за каким столом
 * (занятые — набор номеров) и, по возможности, не ту, с кем этот человек
 * играл только что (недавние — набор номеров). Все заняты — любая
 * незанятая из недавних; совсем никого — null (тогда стол ждёт дальше).
 */
function выбрать(занятые, недавние, случай) {
  const жребий = typeof случай === 'function' ? случай : Math.random;
  const свободные = СПИСОК.filter(function (л) { return !занятые.has(л.номер); });
  if (свободные.length === 0) return null;
  const новые = недавние ? свободные.filter(function (л) { return !недавние.has(л.номер); }) : свободные;
  const откуда = новые.length > 0 ? новые : свободные;
  return откуда[Math.floor(жребий() * откуда.length)];
}

/**
 * Уровень серверного бота для личины в этой игре. обычный — уровень
 * подбора этой игры (как сажали бота раньше); слабый — самый лёгкий;
 * сильный — самый трудный из тех, что знает игра.
 */
function уровеньДляИгры(личина, уровниИгры, обычный) {
  const список = Array.isArray(уровниИгры) && уровниИгры.length ? уровниИгры : ['лёгкий', 'обычный', 'сложный'];
  if (личина.сила === 'слабый') return список[0];
  if (личина.сила === 'сильный') return список[список.length - 1];
  return обычный && список.indexOf(обычный) !== -1 ? обычный : список[Math.floor(список.length / 2)];
}

/* ---------------------------------------------------------------------
   Темп: человек думает по-разному. Срединное время хода по играм
   (секунды) и разброс по логнормальному закону: чаще около середины,
   изредка заметно дольше. Время на ход за столом (лимит) не превышаем:
   личина никогда не «просыпает» ход.
   --------------------------------------------------------------------- */
const СЕРЕДИНА_ХОДА_С = {
  'дурак': 2.4, 'шашки': 3.6, 'шахматы': 5.5, 'нарды': 3.2, 'морской-бой': 2.6,
  'домино': 3.2, 'деберц': 4, 'покер': 4.2, 'монополия': 4.5, 'катан': 5, 'захват': 0
};

function нормальное(жребий) {
  // Бокс — Мюллер: из двух равномерных одно нормальное.
  const u = Math.max(жребий(), 1e-9);
  const v = жребий();
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
}

/**
 * Пауза перед ходом личины, мс. база — пауза, которую игра дала бы
 * обычному боту; лимитС — время на ход за столом (0 — без лимита).
 * У «Захвата» раунд одновременный и паузу он считает сам — её не трогаем.
 */
function паузаХода(игра, база, лимитС, случай) {
  const жребий = typeof случай === 'function' ? случай : Math.random;
  const серединаС = СЕРЕДИНА_ХОДА_С[игра];
  if (!серединаС) return база;
  let мс = серединаС * 1000 * Math.exp(0.45 * нормальное(жребий));
  if (жребий() < 0.08) мс *= 2.2;                  // иногда задумывается всерьёз
  мс = Math.max(мс, Math.max(900, база || 0));     // не быстрее обычного бота
  мс = Math.min(мс, 22000);
  if (лимитС > 0) мс = Math.min(мс, лимитС * 1000 * 0.6);
  return Math.round(мс);
}

/**
 * Что личина делает после партии: 'ещё' — зовёт/соглашается сыграть
 * ещё, 'уходит' — выходит из-за стола. И через сколько миллисекунд.
 */
function послеПартии(случай) {
  const жребий = typeof случай === 'function' ? случай : Math.random;
  if (жребий() < 0.78) return { что: 'ещё', черезМс: Math.round(2000 + жребий() * 5000) };
  return { что: 'уходит', черезМс: Math.round(4000 + жребий() * 8000) };
}

/** Сколько ждать живого соперника, прежде чем посадить личину, мс (8–20 с). */
function ожиданиеДоЛичины(случай) {
  const жребий = typeof случай === 'function' ? случай : Math.random;
  return Math.round(8000 + жребий() * 12000);
}

/* ---------------------------------------------------------------------
   Живые лобби (Э1 плана штаб/план-живые-лобби.md): чистые функции для
   столов личин. Без таймеров и без сервера — только считают и возвращают.
   --------------------------------------------------------------------- */

const ПУЛ_ЛОББИ_ПО_УМОЛЧАНИЮ = 40;   // владелец 09.10: ботов мало — 80 личин, за столами одновременно до 40

/**
 * Личины для столов: сколько штук, каждая — один раз (одна личина — один
 * номер). Имена и фото берём из всего списка, по жребию. По умолчанию 40;
 * число из довода можно поднять до размера всего списка.
 */
function пулЛобби(сколько, случай) {
  const жребий = typeof случай === 'function' ? случай : Math.random;
  const число = Number.isFinite(сколько) ? Math.floor(сколько) : ПУЛ_ЛОББИ_ПО_УМОЛЧАНИЮ;
  const нужно = Math.max(0, Math.min(число, СПИСОК.length));
  const вперемешку = СПИСОК.slice();
  // Тасование Фишера — Йетса: каждая личина попадает в начало с равным шансом.
  for (let i = вперемешку.length - 1; i > 0; i--) {
    const j = Math.floor(жребий() * (i + 1));
    const буфер = вперемешку[i]; вперемешку[i] = вперемешку[j]; вперемешку[j] = буфер;
  }
  return вперемешку.slice(0, нужно);
}

/** Сколько стол личин ждёт гостей до «устала ждать», мс (4–12 минут). */
function срокСтола(случай) {
  const жребий = typeof случай === 'function' ? случай : Math.random;
  return Math.round(4 * 60000 + жребий() * 8 * 60000);
}

