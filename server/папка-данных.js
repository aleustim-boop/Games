const path = require('path');

/* Куда складывать данные, если снаружи ничего не сказали. Та же папка,
   что была зашита в четырёх файлах памяти до появления этого. */
const ПАПКА_ПО_УМОЛЧАНИЮ = path.join(__dirname, 'данные');

/* Имена переменных окружения — по порядку, в каком спрашиваем. */
const ИМЕНА_ПЕРЕМЕННЫХ = ['ДАННЫЕ_ИГРЫ', 'GAMES_DATA'];

/**
 * Папка с данными прямо сейчас. Спрашивается при каждом обращении —
 * см. пояснение в шапке.
 */
function папка() {
  for (const имя of ИМЕНА_ПЕРЕМЕННЫХ) {
    const сказанное = process.env[имя];
    if (typeof сказанное === 'string' && сказанное.trim()) {
      return сказанное.trim();
    }
  }
  return ПАПКА_ПО_УМОЛЧАНИЮ;
}

/** Путь к файлу внутри папки данных. */
function файл(имя) {
  return path.join(папка(), имя);
}

/** Уведена ли папка в сторону — нужно проверкам и записи в консоль. */
function папкаУведена() {
  return папка() !== ПАПКА_ПО_УМОЛЧАНИЮ;
}

module.exports = {
  ПАПКА_ПО_УМОЛЧАНИЮ: ПАПКА_ПО_УМОЛЧАНИЮ,
  ИМЕНА_ПЕРЕМЕННЫХ: ИМЕНА_ПЕРЕМЕННЫХ,
  папка: папка,
  файл: файл,
  папкаУведена: папкаУведена
};
