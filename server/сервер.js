let популярность = require('./популярность.js').создать();

/* Имя заголовка латиницей нарочно: кириллица в имени заголовка HTTP
   запрещена, Node такой запрос даже не отправит. */
const ЗАГОЛОВОК_КЛЮЧА_ШТАБА = 'x-klyuch-shtaba';

/* Заголовки, которые ставят туннель Cloudflare и nginx. Есть хоть один —
   запрос пришёл снаружи, а сводка с номерами наружу не выходит никогда,
   даже с верным ключом: ключ мог утечь, а дверь для чужих не нужна вовсе. */
const ЗАГОЛОВКИ_ТУННЕЛЯ = ['cf-connecting-ip', 'cf-ray', 'x-forwarded-for', 'x-real-ip'];

/* Ключ штаба — в памяти процесса; читается при запуске (см. запустить). */
let ключШтаба = null;

/**
 * Прочитать ключ штаба из папки данных. Файла нет (и только тогда!) и
 * можноСоздать — создать: 32 случайных байта шестнадцатеричными знаками.
 * Папка данных закрыта от git своим .gitignore.
 *
 * Создавать разрешено лишь настоящему серверу с диском: проверочный
 * (--без-памяти или поднятый из проверки) ключ только читает — иначе он
 * мусорил бы ключами в чужих папках. Любая другая беда (нет прав, файл
 * испорчен) — ключа нет, и /штаб-онлайн отказывает всем: перезаписать
 * испорченный файл молча значило бы сменить ключ за спиной у дашборда.
 */
function подготовитьКлючШтаба(можноСоздать) {
  const файл = гдеДанные.файл('ключ-штаба');
  ключШтаба = null;
  let прочитанный;
  try {
    прочитанный = fs.readFileSync(файл, 'utf8').trim();
  } catch (сбой) {
    if (сбой.code === 'ENOENT' && можноСоздать) создатьКлючШтаба(файл);
    else if (сбой.code !== 'ENOENT') console.error('Ключ штаба не прочитан — сводка посещений закрыта для всех.');
    return;
  }
  if (/^[0-9a-f]{64}$/.test(прочитанный)) ключШтаба = прочитанный;
  else console.error('Ключ штаба испорчен — сводка посещений закрыта для всех.');
}

/** Создать файл ключа. Флаг «wx» — не затереть файл, появившийся только что. */
function создатьКлючШтаба(файл) {
  try {
    const новый = crypto.randomBytes(32).toString('hex');
    fs.mkdirSync(path.dirname(файл), { recursive: true });
    fs.writeFileSync(файл, новый + '\n', { encoding: 'utf8', mode: 0o600, flag: 'wx' });
    ключШтаба = новый;
  } catch (сбой) {
    ключШтаба = null;
    console.error('Ключ штаба не создан — сводка посещений закрыта для всех.');
  }
}

/** Пришёл ли запрос через туннель или nginx (есть хоть один их заголовок). */
function пришёлСнаружи(запрос) {
  return ЗАГОЛОВКИ_ТУННЕЛЯ.some(function (имя) { return запрос.headers[имя] !== undefined; });
}

/** Совпал ли присланный ключ со своим. Сравнение за одинаковое время. */
function ключШтабаВерный(присланный) {
  if (!ключШтаба || typeof присланный !== 'string') return false;
  const своё = Buffer.from(ключШтаба, 'utf8');
  const чужое = Buffer.from(присланный, 'utf8');
  return своё.length === чужое.length && crypto.timingSafeEqual(своё, чужое);
}

/** GET /штаб-онлайн — сводка посещений с номерами, только своему дашборду. */
function сводкаДляШтаба(запрос, ответ) {
  if (пришёлСнаружи(запрос)) return ошибка(ответ, 403, 'Нет доступа');
  if (!ключШтабаВерный(запрос.headers[ЗАГОЛОВОК_КЛЮЧА_ШТАБА])) return ошибка(ответ, 403, 'Нет доступа');
  return ответить(ответ, 200, посещения.сводка(Date.now()));
}

/**
 * POST /пульс { initData, игра } → { ок }. Номер и имя — только из
 * проверенной подписи; без подписи ничего не учитываем. В ответе и в
 * журнале номеров нет.
 */
function принятьПульс(тело, ответ) {
  const целое = тело && typeof тело === 'object' ? тело : {};
  const кто = ктоПрислал(целое.initData);
  if (!кто) return ответить(ответ, 200, { ок: false });
  if (целое.каталог) {
    return ответить(ответ, 200, { ок: популярность.учесть(String(кто), целое.игра, целое.каталог) });
  }
  посещения.учесть(String(кто), имяИзПодписи(целое.initData), целое.игра, Date.now());
  return ответить(ответ, 200, { ок: true });
}

