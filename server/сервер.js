/* Сколько держим запрос «что нового» без событий. Меньше минуты —
   чтобы промежуточные железки в сети не рвали соединение молча. */
const ОПРОС_ПО_УМОЛЧАНИЮ = 25 * 1000;

/* Границы разумного. Меньше секунды — сервер и сеть загружены впустую:
   игра будет спрашивать по нескольку раз в секунду ни о чём. Больше
   минуты — почти любой посредник в сети успеет счесть соединение
   брошенным и оборвать его. */
