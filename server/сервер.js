/* Учёт живёт в памяти. На диск пишет только настоящий сервер: при прямом
   запуске без «--без-памяти» его пересоздают с файлом в папке данных —
   тем же приёмом, каким там включают запись статистики. Проверки,
   подключающие сервер как модуль, на диск не пишут вовсе. */
