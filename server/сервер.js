комнаты.слушатьСобытия(событиеСтолаВЛенту);

/* ---------------------------------------------------------------------
   ОТКРЫТЫЕ СТОЛЫ: список тех, к кому можно подсесть прямо сейчас

   Зачем. Сесть за стол можно было только по коду от друга. Владелец
   попросил вторую дорогу: «выбирать игры онлайн, к которым можно
   подключиться и играть». Сервер показывает столы, которые хозяева
   объявили открытыми, и сажает за выбранный стол одним запросом.

   Четыре правила этой двери, и все четыре — не про удобство.

     1) Только для подписи Telegram, как у «знакомых» и рейтинга.
        Списка живых столов анонимному спрашивающему не даём вовсе:
        иначе он становится бесплатной картой сервера для любого скрипта.

     2) Кода стола в списке нет. Вместо него — короткоживущий ключ,
        свой у каждого спрашивающего (см. ключСтола). Код — вещь долгая:
        уехав один раз, он остаётся годным и после того, как хозяин
        стол закрыл. Ключ живёт минуту, годен одному человеку и к одному
        столу, и подобрать его нельзя.

     3) Не чаще раза в секунду на человека. Экран обновляет список раз
        в несколько секунд, живому это не мешает; скребку — мешает.

     4) Садимся не по коду из запроса, а по ключу: чужой стол таким
        запросом не откроешь, сколько кодов ни перебирай.
   --------------------------------------------------------------------- */

/* Сколько живёт ключ стола. Минута — это «успеть нажать «Сесть» на том,
   что видишь»: список обновляется чаще, и каждый обход выдаёт ключ заново.
   Дольше держать нельзя: стол за это время закрывают, и ключ вёл бы
   в комнату, которую уже никто не открывал для всех. */
const КЛЮЧ_СТОЛА_ЖИВЁТ = 60 * 1000;

/* Столько ключей помним разом. Ключей ровно столько, сколько пар
   «человек × стол» показано в последнюю минуту, но потолок нужен:
   память сервера не должна расти от одного лишь разглядывания списка. */
const ПОМНИМ_КЛЮЧЕЙ_СТОЛОВ = 5000;

/* Как часто один человек может просить список. */
const СПИСОК_НЕ_ЧАЩЕ = 1000;
const ПОМНИМ_СМОТРЕВШИХ = 500;

/* Ключ → { код, кто, доКогда } и обратно «кто:код» → ключ.
   Второй нужен, чтобы при каждом обновлении списка не плодить новый ключ
   на тот же стол: человек смотрит список минуту — это шестьдесят ключей
   на ровном месте. */
const ключиСтолов = new Map();
const ключПоПаре = new Map();
const когдаСмотрели = new Map();

/* Столько храним «когда в последний раз смотрели список» на одного
   человека, прежде чем запись можно забыть. Не то же самое, что
   СПИСОК_НЕ_ЧАЩЕ: тот, кто держит экран открытым, обновляет свою запись
   сам каждые несколько секунд, и её и трогать не нужно, а вот того, кто
   заглянул один раз и ушёл, память по нему держать незачем. Пять минут —
   с большим запасом сверх реального интервала обновления экрана. */
const СМОТРЕЛ_ЗАБЫВАЕТСЯ_ЧЕРЕЗ = 5 * 60 * 1000;

/** Выкинуть просроченные ключи. Зовётся при каждой выдаче — этого хватает. */
function прибратьКлючиСтолов(сейчас) {
  for (const [ключ, запись] of ключиСтолов) {
    if (запись.доКогда > сейчас) continue;
    ключиСтолов.delete(ключ);
    ключПоПаре.delete(запись.кто + ':' + запись.код);
  }
  /* Последняя страховка: если ключей всё равно слишком много, выбрасываем
     самые старые. Map хранит записи по порядку добавления, поэтому первые
     в обходе — самые давние. */
  while (ключиСтолов.size > ПОМНИМ_КЛЮЧЕЙ_СТОЛОВ) {
    const первый = ключиСтолов.keys().next();
    if (первый.done) break;
    const запись = ключиСтолов.get(первый.value);
    ключиСтолов.delete(первый.value);
    if (запись) ключПоПаре.delete(запись.кто + ':' + запись.код);
  }
}

/**
 * Ключ этого человека к этому столу. Тот же ключ, пока он не просрочен, —
 * иначе каждое обновление списка плодило бы новый.
 *
 * Сам ключ — случайные 32 байта, а не подпись кода: из подписи код
 * не вынешь, но и хранить в ней его незачем. Пара «ключ → код» лежит
 * только в памяти сервера, наружу код не уходит ни в каком виде.
 */
function ключСтола(кто, код, родиласьТогда, сейчас) {
  const пара = кто + ':' + код;
  const прежний = ключПоПаре.get(пара);
  if (прежний) {
    const запись = ключиСтолов.get(прежний);
    if (запись && запись.доКогда > сейчас) {
      запись.доКогда = сейчас + КЛЮЧ_СТОЛА_ЖИВЁТ;   // продлеваем, пока смотрят
      return прежний;
    }
  }
  const ключ = crypto.randomBytes(24).toString('hex');
  /* «родиласьТогда» — время рождения ИМЕННО ТОЙ комнаты, что стоит за этим
     кодом сейчас: коды конечные и переиспользуются, а ключ живёт минуту.
     Сверяем его при посадке (см. столПоКлючу, сестьЗаСтол), чтобы не
     посадить человека в чужую комнату, которой позже достался тот же код. */
  ключиСтолов.set(ключ, {
    код: код, кто: кто, родиласьТогда: родиласьТогда, доКогда: сейчас + КЛЮЧ_СТОЛА_ЖИВЁТ
  });
  ключПоПаре.set(пара, ключ);
  return ключ;
}

/**
 * Стол по ключу — { код, родиласьТогда } или null, если ключ чужой,
 * просроченный или выдуманный. Ключ годен только тому, кому его выдали:
 * подсмотренный у соседа не подойдёт.
 */
function столПоКлючу(кто, ключ, сейчас) {
  if (typeof ключ !== 'string' || !ключ) return null;
  const запись = ключиСтолов.get(ключ);
  if (!запись || запись.кто !== кто) return null;
  if (запись.доКогда <= сейчас) return null;
  return { код: запись.код, родиласьТогда: запись.родиласьТогда };
}

/** Выкинуть тех, кто список не спрашивал уже долго.
 *
 * Чистим по сроку, а не «первый в очереди на удаление» по порядку
 * добавления: Map.set для уже существующего ключа порядок вставки
 * не меняет — только значение. Значит «первый» в обходе — это тот,
 * кого добавили раньше всех, а не тот, кто дольше всех молчит. Человек,
 * который смотрит список постоянно, но пришёл на сервер раньше других,
 * рисковал попасть под чистку первым — раньше давно ушедшего новичка. */
function прибратьСмотревших(сейчас) {
  for (const [кто, когда] of когдаСмотрели) {
    if (сейчас - когда > СМОТРЕЛ_ЗАБЫВАЕТСЯ_ЧЕРЕЗ) когдаСмотрели.delete(кто);
  }
  // Последняя страховка: очень много разных людей разом, срок ещё не вышел.
  while (когдаСмотрели.size > ПОМНИМ_СМОТРЕВШИХ) {
    const первый = когдаСмотрели.keys().next();
    if (первый.done) break;
    когдаСмотрели.delete(первый.value);
  }
}

/** Не частит ли этот человек с просьбой показать список. */
function списокПроситьРано(кто, сейчас) {
  const прошлый = когдаСмотрели.get(кто);
  if (прошлый !== undefined && сейчас - прошлый < СПИСОК_НЕ_ЧАЩЕ) return true;
  прибратьСмотревших(сейчас);
  когдаСмотрели.set(кто, сейчас);
  return false;
}

/**
 * POST /открытые-столы — { initData, игра? } → список столов со свободными
 * местами. Ответ собираем вручную, поле за полем: наружу идут игра, числа
 * мест, имена сидящих и ключ; кода стола и номеров Telegram в нём нет.
 */
function списокОткрытыхСтолов(тело, ответ) {
  const кто = ктоПрислал(тело && тело.initData);
  if (!кто) {
    return ответить(ответ, 200, {
      ок: false,
      узналиВас: false,
      столы: [],
      причина: 'Найти игру можно только в Telegram: иначе одного игрока ' +
               'не отличить от другого'
    });
  }

  const сейчас = Date.now();
  if (списокПроситьРано(кто, сейчас)) {
    return ответить(ответ, 429, {
      ок: false,
      узналиВас: true,
      столы: [],
      причина: 'Список обновляется не так часто — подождите секунду'
    });
  }
  прибратьКлючиСтолов(сейчас);

  const игра = тело && typeof тело.игра === 'string' ? тело.игра : '';
  const столы = [];
  for (const стол of комнаты.открытыеСтолы(игра)) {
    /* Имена перекладываем поодиночке и только строками: разложить готовую
       запись целиком (спред, Object.assign) нельзя — вместе с ней уехал бы
       код стола, который комнаты кладут в строку для нас, а не для игрока. */
    const имена = [];
    for (const имя of стол.игроки) имена.push(String(имя));
    столы.push({
      ключ: ключСтола(кто, стол.код, стол.родиласьТогда, сейчас),
      игра: стол.игра,
      мест: стол.мест,
      занято: стол.занято,
      свободно: стол.свободно,
      игроки: имена,
      ботов: стол.ботов,
      правилаСтола: стол.правилаСтола,
      ждётСекунд: стол.ждётСекунд
    });
  }
  return ответить(ответ, 200, { ок: true, узналиВас: true, столы: столы });
}

/**
 * POST /сесть — { initData, ключ, имя?, метка? } → сесть за выбранный стол.
 * Отвечает тем же, чем «войти»: код комнаты, пропуск и первый вид стола.
 *
 * Код здесь впервые уходит игроку — и это правильно: он уже за столом,
 * и код нужен ему для всей дальнейшей жизни в комнате (опросы, возврат
 * после обрыва). Пока человек за стол не сел, кода он не знает.
 */
function сестьЗаСтол(тело, запрос, ответ) {
  const оборвалось = следитьЗаОбрывом(запрос, ответ);
  const целое = отметитьКтоЭто(тело);
  const кто = целое.телеграм;
  if (!кто) {
    return ошибка(ответ, 403, 'Сесть за открытый стол можно только из Telegram');
  }

  const найденный = столПоКлючу(кто, целое.ключ, Date.now());
  if (!найденный) {
    return ошибка(ответ, 404,
      'Этот стол больше не в списке — обновите список и выберите другой');
  }
  const код = найденный.код;

  /* Между показом списка и нажатием проходят секунды: стол успевает
     закрыться, заполниться или начать партию — а то и вовсе смениться:
     коды переиспользуются, и родиласьТогда сверяет, что это та же самая
     комната, что была в списке. Отвечаем словами, чтобы человек понял,
     почему он не сел. */
  const можноЛи = комнаты.столОткрытДляПосадки(код, найденный.родиласьТогда);
  if (!можноЛи.можно) return ошибка(ответ, 409, можноЛи.причина);

  /* Дальше — обычный вход, тот же самый, что по коду от друга: он один
     сажает за стол, он же и решает гонку «нажали разом» (место занимает
     тот, чей запрос пришёл первым, второму честно отвечают, что мест нет). */
  const итог = комнаты.войтиВКомнату(код, {
    имя: целое.имя,
    метка: целое.метка,
    телеграм: кто
  });
  if (!итог.ок) return ошибка(ответ, 409, итог.причина);

  /* Место заняли, а получить ответ уже некому: человек не дождался
     и закрыл игру. Отдаём место обратно — иначе стол закроется
     на призрака, как это было на двери «войти» до той же правки. */
  if (оборвалось()) {
    комнаты.отменитьВход(итог.код, итог.пропуск);
    return;
  }

  /* Ключ сработал — второй раз он не нужен: человек уже за столом,
     а место у стола одно. */
  const запись = ключиСтолов.get(целое.ключ);
  if (запись) {
    ключиСтолов.delete(целое.ключ);
    ключПоПаре.delete(запись.кто + ':' + запись.код);
  }

  ответить(ответ, 200, {
    код: итог.код,
    пропуск: итог.пропуск,
    состояние: итог.состояние
  });
}

/* ---------------------------------------------------------------------
   ПОДБОР СОПЕРНИКА: «Играть онлайн» без кода и без выбора чужого стола

   В отличие от «Открытых столов» выше (человек сам смотрит список и жмёт
   «Сесть»), тут сервер сводит пару сам: двое с одинаковыми правилами
   встают в очередь (server/подбор.js), и как только нашёлся второй —
   обоих сажают за один стол без единого действия руками. Не нашёлся
   никто за отведённое время — соперником становится бот.

   Личность — только из подписи Telegram (ктоПрислал), как у «знакомых»
   и «открытых столов»: анонимного игрока не отличить от другого, а
   очередь на двоих обязана свести именно тех, кто её попросил.

   Модуль подбора ничего не знает про HTTP и про комнаты (см. его же
   шапку) — сведение пары в комнату целиком собрано здесь, в одной общей
   функции для обеих дверей (/подбор и /подбор-новости), чтобы протокол
   сведения не раздваивался (см. свестиПаруПодбора).
   --------------------------------------------------------------------- */

/* Уровень бота, которого подбор подсаживает не дождавшемуся соперника
   игроку. Решение штаба (план-онлайн-подбор.md, п.3): всегда «обычный» —
   подбор ищет РАВНОГО человека, а не бота какой-то сложности, выбор
   уровня здесь ни при чём. */
const УРОВЕНЬ_БОТА_ОТ_ПОДБОРА = 'обычный';

/* Шаг опроса подбор.статус() внутри длинного опроса /подбор-новости.
   Модуль подбора не умеет будить нас сам — у него нет событий (см. его
   шапку: он ничего не знает про HTTP), поэтому только периодический
   опрос. Синхронный while-опрос тут недопустим: он держал бы весь
   процесс и останавливал бы ВСЕ идущие партии на время ожидания —
   опрашиваем через повторяющийся setTimeout. */
const ШАГ_ОПРОСА_ПОДБОРА = 500;

/**
 * Кто стоит за каждым ключОжидания — сервер должен знать это сам.
 *
 * Модуль подбора не хранит и не отдаёт наружу личность ждущего через
 * подбор.статус(ключОжидания) (см. его шапку: там нарочно нет ничего
 * про HTTP и подпись Telegram) — статус несёт только сКем (партнёра).
 * А дверь /подбор-новости получает от клиента ТОЛЬКО ключОжидания, без
 * initData: узнать «кто это» из самого запроса ей нечем. Между тем
 * знать «кто это» здесь необходимо взаправду — не для красоты: и чтобы
 * посчитать ключ пары в свестиПаруПодбора, и чтобы посадить ЭТОГО
 * человека за стол, когда пришло «пора_бота» (в этот момент он ждал
 * один, и посадить бота нужно именно к нему).
 *
 * Поэтому здесь же, в сервере, заводим маленькую свою память:
 * ключОжидания → кто такой (номер Telegram, имя, правило «переводной»).
 * Заполняется в момент /подбор, где initData точно есть; читается
 * в /подбор-новости, где initData уже нет. Запись убирается сразу, как
 * только становится не нужна (свели, посадили бота, ключ не найден),
 * а на случай брошенной вкладки, которая перестала опрашивать вовсе —
 * чистится по времени, тем же приёмом, что и ключиСтолов чуть выше. */
const ПОМНИМ_ЛИЧНОСТЬ_ОЖИДАНИЯ_МС = 5 * 60 * 1000;
const ПОМНИМ_ЛИЧНОСТЕЙ_ОЖИДАНИЯ = 1000;
const личностьПоКлючуОжидания = new Map();

function запомнитьЛичностьОжидания(ключОжидания, кто, имя, переводной) {
  личностьПоКлючуОжидания.set(ключОжидания, {
    кто: кто, имя: имя, переводной: переводной, записано: Date.now()
  });
  while (личностьПоКлючуОжидания.size > ПОМНИМ_ЛИЧНОСТЕЙ_ОЖИДАНИЯ) {
    const первый = личностьПоКлючуОжидания.keys().next();
    if (первый.done) break;
    личностьПоКлючуОжидания.delete(первый.value);
  }
}

function забытьЛичностьОжидания(ключОжидания) {
  личностьПоКлючуОжидания.delete(ключОжидания);
}

/** Выкинуть личности брошенных ожиданий — тех, о ком давно не спрашивали. */
function прибратьЛичностиОжидания() {
  const сейчас = Date.now();
  for (const [ключ, запись] of личностьПоКлючуОжидания) {
    if (сейчас - запись.записано > ПОМНИМ_ЛИЧНОСТЬ_ОЖИДАНИЯ_МС) личностьПоКлючуОжидания.delete(ключ);
  }
}

/** Пара «кто ждёт» → «код и пропуск для второго».
 *
 * Нужна ровно на миг между тем, как одна сторона узнала «свели» и
 * создала комнату на двоих, и тем, как об этом же сведении узнает
 * вторая сторона (тем же или следующим опросом). Обе стороны вычисляют
 * ключ одинаково (см. ключПарыПодбора) независимо от того, кто из них
 * первым это делает, поэтому запись правильно находит и создателя,
 * и того, кто зашёл за ней следом, и того, кто спросил ПОВТОРНО (сеть
 * потеряла первый ответ) — повтор просто найдёт то же самое, ничего
 * не создавая заново. */
const парыПодбора = new Map();

/** Ключ пары — не зависит от того, кто из двоих его считает первым:
 * сортируем номера Telegram как числа, а не как строки. */
function ключПарыПодбора(а, б) {
  return Math.min(а, б) + ':' + Math.max(а, б);
}

/**
 * Задать комнате «переводной» в обход применитьНастройки (комнаты.js).
 *
 * Почему не через настройки создатьКомнату. Там ЛЮБАЯ понятая настройка
 * (в том числе «переводной») включает комнате «компанию» — прихожую
 * с кнопкой «Начать» для хозяина (см. создатьКомнату: «если применили
 * хоть одну настройку — компания = true»). Для сведённой подбором пары
 * это не годится: подбор обещает игру сразу, как только соперник
 * найден — «стол на двоих стартует сам, без кнопки «Начать», когда
 * стол не «компания»» (план-онлайн-подбор.md, раздел «Что уже есть»).
 * Поэтому правило ставим тем же присваиванием, что и применитьНастройки
 * делает внутри комнаты.js, но отдельно — «компанию» не трогая. Больше
 * это поле ни на что не влияет: раздатьПартию просто читает его как
 * есть. Другого пути передать это правило внутрь комнаты в обход
 * компании comнаты.js сегодня не предоставляет. */
function применитьПереводнойБезКомпании(комната, переводной) {
  комната.переводной = !!переводной;
}

/**
 * Свести пару, о которой подбор.js только что сказал «статус: свели»,
 * в комнату. Общая для дверей /подбор и /подбор-новости — правило
 * CLAUDE.md против раздвоения сетевого протокола.
 *
 * Первая из двух сторон, что сюда попадёт (для этой пары в парыПодбора
 * ещё пусто), создаёт комнату и сажает в неё сразу обоих — это не
 * подделка личности партнёра: подбор.js только что реально свёл этих
 * двоих, и оба их имени и номера у нас на руках. Вторая сторона просто
 * забирает то, что первая для неё оставила. Вызовы синхронные, без
 * await между проверкой и записью в Map — Node однопоточный, гонка
 * с параллельным запросом партнёра исключена.
 *
 * Возвращает { ок: true, код, пропуск } или { ок: false, причина }
 * словами, понятными игроку (не должно случаться в норме — комната
 * только что создана специально под эту пару).
 */
function свестиПаруПодбора(кто, имя, сКем, переводной) {
  const ключ = ключПарыПодбора(кто, сКем.номерТелеграм);
  const готовое = парыПодбора.get(ключ);
  if (готовое) {
    парыПодбора.delete(ключ);
    return { ок: true, код: готовое.код, пропуск: готовое.пропускВторого };
  }

  const создано = комнаты.создатьКомнату(null, { имя: имя, телеграм: кто });
  if (!создано.ок) return { ок: false, причина: создано.причина };

  /* Комнату сейчас видит только что созданный первый игрок — вид объекта
     берём тем же приёмом, каким его берут другие места файла (найтиИгрока
     по коду и своему пропуску), другого способа получить объект комнаты
     по коду наружу не экспортировано. */
  const первый = комнаты.найтиИгрока(создано.код, создано.пропуск);
  if (!первый) {
    return { ок: false, причина: 'Не получилось усадить за стол — попробуйте ещё раз' };
  }
  применитьПереводнойБезКомпании(первый.комната, переводной);

  const вошёлВторой = комнаты.войтиВКомнату(создано.код, {
    имя: сКем.имя, телеграм: сКем.номерТелеграм
  });
  if (!вошёлВторой.ок) return { ок: false, причина: вошёлВторой.причина };

  парыПодбора.set(ключ, { код: создано.код, пропускВторого: вошёлВторой.пропуск });
  return { ок: true, код: создано.код, пропуск: создано.пропуск };
}

/**
 * Посадить бота на пустое место одиночке, которого подбор не свёл ни
 * с кем за отведённое время. Общая для /подбор-новости («пора_бота»
 * из статуса) — единственного места, откуда этот сигнал приходит.
 */
function усадитьОдногоСБотом(личность) {
  const создано = комнаты.создатьКомнату(null, { имя: личность.имя, телеграм: личность.кто });
  if (!создано.ок) return { ок: false, причина: создано.причина };

  const первый = комнаты.найтиИгрока(создано.код, создано.пропуск);
  if (!первый) {
    return { ок: false, причина: 'Не получилось усадить за стол — попробуйте ещё раз' };
  }
  применитьПереводнойБезКомпании(первый.комната, личность.переводной);

  const посадка = комнаты.посадитьБотаОтПодбора(первый.комната, УРОВЕНЬ_БОТА_ОТ_ПОДБОРА);
  if (!посадка.принято) return { ок: false, причина: посадка.причина };

  return { ок: true, код: создано.код, пропуск: создано.пропуск };
}

/**
 * POST /подбор — { initData, местВСтоле?, переводной? } → встать в
 * очередь на соперника с такими же правилами. Отвечает тем же, чем
 * ответил бы длинный опрос, если бы соперник нашёлся мгновенно: либо
 * «ждите» с ключом ожидания, либо сразу «свели», код и пропуск за
 * столом. Только 1×1 (план-онлайн-подбор.md, «Объём подбора») — игра
 * всегда «дурак», местВСтоле не выбирают.
 */
function подборВстатьВОчередь(тело, ответ) {
  const кто = ктоПрислал(тело && тело.initData);
  if (!кто) {
    return ответить(ответ, 200, {
      ок: false,
      причина: 'Играть онлайн можно только в Telegram: иначе одного ' +
               'игрока не отличить от другого'
    });
  }

  прибратьЛичностиОжидания();
  const имя = имяИзПодписи(тело.initData);
  const переводной = !!(тело && тело.переводной);

  const итог = подбор.встатьВОчередь({
    номерТелеграм: кто, имя: имя, метка: (тело && тело.метка) || '',
    игра: 'дурак', местВСтоле: 2, переводной: переводной
  });

  if (итог.статус === 'свели') {
    забытьЛичностьОжидания(итог.ключОжидания);
    const комната = свестиПаруПодбора(кто, имя, итог.сКем, переводной);
    if (!комната.ок) return ответить(ответ, 200, { ок: false, причина: комната.причина });
    return ответить(ответ, 200, { статус: 'свели', код: комната.код, пропуск: комната.пропуск });
  }

  // статус: 'ждёт' — запоминаем, кто это, для будущих /подбор-новости.
  запомнитьЛичностьОжидания(итог.ключОжидания, кто, имя, переводной);
  return ответить(ответ, 200, {
    статус: 'ждёт', ключОжидания: итог.ключОжидания, доБота: итог.доБота
  });
}

/**
 * POST /подбор-новости — { ключОжидания } → длинный опрос статуса
 * ожидания, устроен как /что-нового: ответ держим, пока не сведена пара,
 * не подсажен бот или не вышло время (тогда { изменилось:false } —
 * клиент спросит снова).
 */
function подборНовости(тело, запрос, ответ) {
  const ключОжидания = тело && typeof тело.ключОжидания === 'string' ? тело.ключОжидания : '';
  if (!ключОжидания) {
    return ответить(ответ, 200, { изменилось: true, статус: 'не_найдено' });
  }

  прибратьЛичностиОжидания();
  const срокДо = Date.now() + длительностьОпроса;
  let таймер = null;
  let завершено = false;

  function закончить(тело) {
    if (завершено) return;
    завершено = true;
    if (таймер) clearTimeout(таймер);
    ответить(ответ, 200, тело);
  }

  /* Тот же приём, что у /что-нового: 'close' само по себе не всегда
     обрыв (бывает и у живого гостя, как только дочитано тело), но пока
     мы держим долгий опрос и ничего не отправили, оно приходит ровно
     в момент настоящего разрыва — тогда writableEnded ещё false. */
  ответ.on('close', function () {
    if (!ответ.writableEnded) {
      завершено = true;
      if (таймер) clearTimeout(таймер);
    }
  });

  function шаг() {
    if (завершено) return;
    const итог = подбор.статус(ключОжидания);

    if (итог.статус === 'не_найдено') {
      забытьЛичностьОжидания(ключОжидания);
      return закончить({ изменилось: true, статус: 'не_найдено' });
    }

    if (итог.статус === 'ждёт') {
      if (Date.now() >= срокДо) return закончить({ изменилось: false });
      таймер = setTimeout(шаг, ШАГ_ОПРОСА_ПОДБОРА);
      return;
    }

    const личность = личностьПоКлючуОжидания.get(ключОжидания);

    if (итог.статус === 'свели') {
      забытьЛичностьОжидания(ключОжидания);
      if (!личность) {
        /* Не должно случаться в норме: запись о личности пропала раньше
           самого ожидания в подбор.js (например, слишком долго не
           опрашивали и её вычистили по времени — см. ПОМНИМ_ЛИЧНОСТЬ_
           ОЖИДАНИЯ_МС). Без неё пару не свести — честно говорим «не
           найдено», клиент начнёт подбор заново. */
        return закончить({ изменилось: true, статус: 'не_найдено' });
      }
      const комната = свестиПаруПодбора(личность.кто, личность.имя, итог.сКем, личность.переводной);
      if (!комната.ок) {
        return закончить({ изменилось: true, ок: false, причина: комната.причина });
      }
      return закончить({
        изменилось: true, статус: 'свели', код: комната.код, пропуск: комната.пропуск
      });
    }

    if (итог.статус === 'пора_бота') {
      забытьЛичностьОжидания(ключОжидания);
      подбор.отменить(ключОжидания);
      if (!личность) {
        return закончить({ изменилось: true, статус: 'не_найдено' });
      }
      const комната = усадитьОдногоСБотом(личность);
      if (!комната.ок) {
        return закончить({ изменилось: true, ок: false, причина: комната.причина });
      }
      // С точки зрения клиента бот ничем не отличается от свежесведённого
      // человека — дальше игра идёт обычным путём /состояние и /что-нового.
      return закончить({
        изменилось: true, статус: 'свели', код: комната.код, пропуск: комната.пропуск
      });
    }

    // На случай статуса, которого сегодня не бывает: не виснем молча.
    return закончить({ изменилось: false });
  }

  шаг();
}

/** POST /подбор-отмена — { ключОжидания } → выйти из очереди подбора. */
function подборОтмена(тело, ответ) {
  const ключОжидания = тело && typeof тело.ключОжидания === 'string' ? тело.ключОжидания : '';
  забытьЛичностьОжидания(ключОжидания);
  const результат = подбор.отменить(ключОжидания);
  return ответить(ответ, 200, { ок: результат.ок });
}

/* ---------------------------------------------------------------------
   Рейтинг: кто играет сильнее

   Дверь устроена как «знакомые», и по той же причине: опознать
   спрашивающего можно только по подписи Telegram. Без неё мы не знаем,
   чьё место показывать, — и отвечаем словами, а не пустой таблицей.

   Ответ собирается вручную, поле за полем, внутри server/рейтинг.js.
   Номера Telegram оттуда не выходят вовсе: наружу едут место, имя,
   очки, победы и число партий.
   --------------------------------------------------------------------- */
function таблицаРейтинга(тело, ответ) {
  const игра = тело && typeof тело.игра === 'string' && тело.игра ? тело.игра : 'дурак';
  const кто = ктоПрислал(тело && тело.initData);

  if (!кто) {
    /* Игра открыта не в Telegram: человека не опознать, а показывать
       чужую таблицу без его собственного места незачем — она бесполезна
       и вдобавок показывала бы чужие имена тому, кто в игре не участвует. */
    return ответить(ответ, 200, {
      ок: false,
      узналиВас: false,
      игра: игра,
      причина: 'Рейтинг ведётся только для игры в Telegram: ' +
               'иначе игрока не отличить от другого'
    });
  }

  const срез = рейтинг.срезСоВсемиПравилами(игра, кто);
  return ответить(ответ, 200, {
    ок: true,
    узналиВас: true,
    игра: срез.игра,
    всего: срез.всего,
    яВТаблице: срез.яВТаблице,
    я: срез.я,
    верхушка: срез.верхушка,
    вокругМеня: срез.вокругМеня,
    /* Вторая мера — сила: кто играет сильнее, а не кто больше сыграл.
       Собрана вручную, поле за полем, в server/сила-игроков.js; номеров
       Telegram внутри нет. */
    сила: срез.сила,
    /* Отдельный счёт по правилу партии (подкидной/переводной), поле за
       полем — собрано в server/рейтинг.js. */
    поПравилу: срез.поПравилу
  });
}

/* ---------------------------------------------------------------------
   Раздача дня: свой итог против остальных

   Игра раз в день предлагает одну и ту же раздачу всем (колода по зерну
   из даты). Сюда приносят результат и здесь же узнают, как сыграли
   остальные. Личность — только из подписи Telegram: иначе один человек
   писал бы результаты за десятерых. Наружу — одни числа, ни имён,
   ни номеров (см. server/раздача-дня.js).
   --------------------------------------------------------------------- */

/**
 * POST /раздача-дня. Два дела одной дверью:
 *   { initData, день, исход, ходов } — записать результат и получить сводку;
 *   { initData?, день }              — только сводка (без исхода ничего не пишем).
 * Ответ всегда 200 и всегда со сводкой — даже при отказе: строка «сегодня
 * выиграли N из M» нужна человеку и тогда, когда его результат не приняли.
 *   { ок, узналиВас, причина, день, сыграли, выиграли, среднийХодПобедителей, моёМесто }
 */
/** Имя игры из запроса — только знакомое слово, остальное считаем дураком. */
function типичнаяИграЗапроса(игра) {
  return игра === 'шашки' ? 'шашки' : 'дурак';
}

function раздачаДняИгрока(тело, ответ) {
  const целое = тело && typeof тело === 'object' ? тело : {};
  const кто = ктоПрислал(целое.initData);
  const день = typeof целое.день === 'string' ? целое.день : '';

  /* Раздача дня — про карты: она сравнивает, как разные люди сыграли ОДНУ
     И ТУ ЖЕ сданную колоду. В шашках раздачи нет вовсе — позиция всегда
     одна и та же, — поэтому отвечаем словами, а не пустой сводкой:
     пустые нули человек читает как «никто сегодня не играл», и это неправда.
     Старые страницы поля «игра» не присылают и попадают в прежнюю ветку. */
  if (типичнаяИграЗапроса(целое.игра) === 'шашки') {
    return ответить(ответ, 200, {
      ок: false,
      узналиВас: Boolean(кто),
      день: день,
      причина: 'В шашках раздачи дня нет: позиция в начале партии всегда одна и та же'
    });
  }

  // Исхода нет — спрашивают сводку, а не сдают результат.
  if (целое.исход === undefined) {
    return ответить(ответ, 200, Object.assign(
      { ок: true, узналиВас: Boolean(кто), причина: '' },
      раздачаДня.сводка(день, кто)));
  }
  if (!кто) {
    return ответить(ответ, 200, Object.assign(
      { ок: false, узналиВас: false, причина: 'Результат записывается только из Telegram' },
      раздачаДня.сводка(день, null)));
  }
  const итог = раздачаДня.записать(день, кто, целое.исход, целое.ходов);
  return ответить(ответ, 200, Object.assign(
    { ок: итог.ок === true, узналиВас: true, причина: итог.причина || '' },
    раздачаДня.сводка(день, кто)));
}

/** GET /раздача-дня?день=2026-09-07[&initData=…] — сводка; «моё место» только с подписью. */
function сводкаРаздачиДня(запрос, ответ) {
  const адрес = new URL(запрос.url, 'http://localhost');
  const день = адрес.searchParams.get('день') || адрес.searchParams.get('day') || '';
  const кто = ктоПрислал(адрес.searchParams.get('initData') || '');
  return ответить(ответ, 200, Object.assign(
    { ок: true, узналиВас: Boolean(кто), причина: '' },
    раздачаДня.сводка(день, кто)));
}

/* ---------------------------------------------------------------------
   Билет на партию с ботом: очки рейтинга за игру в браузере

   Партия с ботом идёт в браузере, и сервер её не видит. Поэтому до
   партии браузер берёт билет (кто, во что, против какого бота, когда
   начал), а после — приносит билет и исход. Уровень бота записан в билет
   до исхода, и подменить его после партии нельзя; от партии без игры
   держат только дневной потолок и замедление — подробно и честно
   об этом в шапке server/билеты.js.

   Личность — только из подписи Telegram, как у раздачи дня. Частоту
   держит server/билеты.js по номеру игрока: билет — не чаще раза в десять
   секунд, сдача — не чаще раза в сорок и не больше двадцати в сутки.
   Шлагбаум здесь стоит только ради общего аварийного клапана при
   ненормальном напоре; неудачей ему ничто из этих дверей не считается.
   Выдуманный билет (128 бит) не подобрать, а за туннелем у всех гостей
   один адрес: неудачи от честных игроков с потерянным билетом (перезапуск
   сервера) тормозили бы всем вход в комнаты.
   --------------------------------------------------------------------- */

const БЕЗ_TELEGRAM_ОЧКОВ_НЕТ = 'Очки за партии с ботом начисляются только в Telegram';

/**
 * Имя из подписи — чтобы в таблице рейтинга стояло имя и у того, кто
 * играет только с ботами. Зовём ТОЛЬКО после проверки подписи
 * («ктоПрислал»): непроверенной строке верить нельзя ни в чём.
 */
function имяИзПодписи(initData) {
  try {
    const кто = JSON.parse(new URLSearchParams(initData).get('user') || 'null');
    const имя = кто && (кто.first_name || кто.username);
    return typeof имя === 'string' ? имя : '';
  } catch (сбой) {
    return '';
  }
}

/** POST /билет { initData, игра, уровень } → { ок, узналиВас, билет, партияНеКорочеСекунд, причина }. */
async function выдатьБилет(тело, запрос, ответ) {
  const очередь = await шлагбаум.пропустить(адресГостя(запрос));
  if (!очередь.можно) return ошибка(ответ, 429, очередь.причина);
  if (живогоСоединенияНет(запрос)) return;   // спрашивавший не дождался

  const целое = тело && typeof тело === 'object' ? тело : {};
  const кто = ктоПрислал(целое.initData);
  if (!кто) return ответить(ответ, 200, { ок: false, узналиВас: false, билет: '', причина: БЕЗ_TELEGRAM_ОЧКОВ_НЕТ });

  const итог = билеты.выдать(кто, целое.игра, целое.уровень);
  return ответить(ответ, 200, {
    ок: итог.ок === true,
    узналиВас: true,
    билет: итог.ок ? итог.билет : '',
    партияНеКорочеСекунд: итог.ок ? итог.партияНеКорочеСекунд : 0,
    причина: итог.причина || ''
  });
}

/** POST /итог-с-ботом { initData, билет, исход } → { ок, узналиВас, очков, причина }. */
async function итогСБотом(тело, запрос, ответ) {
  const очередь = await шлагбаум.пропустить(адресГостя(запрос));
  if (!очередь.можно) return ошибка(ответ, 429, очередь.причина);
  if (живогоСоединенияНет(запрос)) return;

  const целое = тело && typeof тело === 'object' ? тело : {};
  const кто = ктоПрислал(целое.initData);
  if (!кто) return ответить(ответ, 200, { ок: false, узналиВас: false, очков: 0, причина: БЕЗ_TELEGRAM_ОЧКОВ_НЕТ });

  /* Из тела берём ровно билет и исход. Уровень, число ботов и прочее,
     что браузер мог дописать, сюда не передаётся вовсе. */
  const итог = билеты.погасить(кто, целое.билет, целое.исход, имяИзПодписи(целое.initData));
  return ответить(ответ, 200, {
    ок: итог.ок === true,
    узналиВас: true,
    очков: итог.ок ? итог.очков : 0,
    причина: итог.причина || ''
  });
}

