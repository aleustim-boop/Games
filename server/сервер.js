'use strict';

/* =====================================================================
   Сервер игры вдвоём. Запускается на домашнем компьютере:

       node server/сервер.js            порт 8765
       node server/сервер.js 8790       если 8765 занят

   Ничего, кроме самого Node, не нужно: ни библиотек, ни базы данных.

   Почему длинные опросы, а не постоянное соединение (WebSocket):
   «Дурак» — игра ходовая, задержка в полсекунды незаметна, а постоянное
   соединение пришлось бы писать руками. Здесь всё проще: клиент
   спрашивает «что нового», сервер придерживает ответ до события
   или до конца отведённого времени и отвечает.

   Что умеет сервер (все ответы — JSON):

     GET  /здоровье     жив ли сервер и сколько сейчас комнат
     POST /создать      создать комнату      → { код, пропуск, состояние }
     POST /войти        { код }              → { пропуск, состояние }
     POST /состояние    { код, пропуск }     → состояние прямо сейчас
     POST /что-нового   { код, пропуск, версия } → ответ придёт по событию
     POST /ход          { код, пропуск, действие, карта, пара }
     POST /выйти        { код, пропуск }

   Действия в запросе /ход: 'ходить' (карта), 'отбить' (пара, карта),
   'беру', 'бито' и 'ещё' — предложить сыграть ещё партию, когда
   предыдущая закончилась.

   Настройки (обе необязательные, лежат в bot/.env рядом с настройками бота):
     GAME_SERVER_PORT    порт, если не подходит 8765;
     GAME_SERVER_ORIGIN  ещё один адрес страницы, которой разрешено
                         обращаться к серверу, — на случай публикации
                         игры в новом месте.

   Пропуск — секретный ключ игрока, его выдают при создании комнаты
   или при входе. Он нужен в каждом запросе: по нему игрок возвращается
   в свою партию после обрыва связи, и он же не даёт ходить за соперника.

   Правила игры сервер не выдумывает: они лежат в js/game.js — там же,
   откуда их берёт браузер. Клиенту верить нельзя, поэтому каждый ход
   проверяется здесь заново.
   ===================================================================== */

const http = require('http');
const fs = require('fs');
const path = require('path');
const комнаты = require('./комнаты.js');
const шлагбаум = require('./шлагбаум.js');

/* Сколько держим запрос «что нового» без событий. Меньше минуты —
   чтобы промежуточные железки в сети не рвали соединение молча. */
const ДЛИТЕЛЬНОСТЬ_ОПРОСА = 25 * 1000;

/* Больше этого тело запроса быть не может: там всегда пара чисел
   и короткий код. Ограничение — от мусора и от случайной заливки. */
const МАКСИМУМ_ТЕЛА = 4 * 1024;

const ПОРТ_ПО_УМОЛЧАНИЮ = 8765;

/* ---------------------------------------------------------------------
   Настройки
   --------------------------------------------------------------------- */

/**
 * Настройки берём из того же файла, что и бот — bot/.env.
 * Файла может не быть вовсе: тогда работаем на порту по умолчанию.
 * Ничего, кроме нужной строки, отсюда не читаем и никуда не выводим —
 * в этом файле лежит токен бота.
 */
function прочитатьНастройки(другойФайл) {
  const файл = другойФайл || path.join(__dirname, '..', 'bot', '.env');
  const настройки = Object.create(null);
  let текст = '';
  try {
    текст = fs.readFileSync(файл, 'utf8');
  } catch (ошибка) {
    return настройки;   // файла нет — это не беда
  }
  for (const строка of текст.split(/\r?\n/)) {
    const обрезанная = строка.trim();
    if (!обрезанная || обрезанная.startsWith('#')) continue;
    const знак = обрезанная.indexOf('=');
    if (знак === -1) continue;
    настройки[обрезанная.slice(0, знак).trim()] = обрезанная.slice(знак + 1).trim();
  }
  return настройки;
}

/** Похоже ли это на настоящий номер порта. */
function номерПортаГодится(число) {
  return Number.isInteger(число) && число > 0 && число < 65536;
}

/**
 * Откуда берём порт, по порядку:
 *   1) номер, написанный при запуске: node server/сервер.js 8790;
 *   2) строка GAME_SERVER_PORT в файле bot/.env;
 *   3) 8765 — если ничего не указано.
 *
 * Номер при запуске стоит первым нарочно: если привычный порт занят
 * чем-то посторонним, человек должен иметь возможность взять другой,
 * не открывая файл с токеном бота.
 */
function выбратьПорт(изКоманднойСтроки) {
  if (изКоманднойСтроки !== undefined && изКоманднойСтроки !== null && изКоманднойСтроки !== '') {
    const указанный = Number(изКоманднойСтроки);
    if (!номерПортаГодится(указанный)) {
      console.error('Не понял номер порта: «' + изКоманднойСтроки + '».');
      console.error('Нужно целое число от 1 до 65535, например: node server/сервер.js 8790');
      process.exit(1);
    }
    return указанный;
  }

  const изФайла = Number(прочитатьНастройки().GAME_SERVER_PORT);
  if (номерПортаГодится(изФайла)) return изФайла;
  return ПОРТ_ПО_УМОЛЧАНИЮ;
}

/* ---------------------------------------------------------------------
   Мелочи для ответов
   --------------------------------------------------------------------- */

/* Откуда игре разрешено обращаться к серверу.

   Страница игры и сервер живут на разных адресах, поэтому браузер
   спрашивает у сервера разрешения. Раньше здесь стояла звёздочка —
   «пускаем всех», и любой сайт мог бы дёргать сервер игры у человека,
   который просто открыл этот сайт. Поэтому круг сужен до двух:
     — опубликованная игра;
     — свой же компьютер (нужно для проверок и игры без интернета).

   Чего этот список НЕ делает. Он не защищает сервер от программ: заголовок
   «Origin» шлёт только браузер, а запрос из скрипта его не шлёт вовсе
   и проходит свободно (см. источникРазрешён ниже). Список — правило
   для чужих страниц, не для чужих программ.

   От программы, которая в цикле создаёт комнаты, полной защиты нет
   ни здесь, ни где-либо ещё: сервер не умеет отличать скрипт от человека.
   Есть только смягчение — потеснитьЖадного в комнаты.js. Когда мест
   не хватает, сервер отбирает место не у первого попавшегося, а у того
   адреса, который держит больше всех забытых комнат: тех, где не сделали
   ни одного хода и о которых давно никто не спрашивал. Живому игроку это
   даёт шанс войти, но пока забытые комнаты не состарились (полминуты),
   он всё равно услышит «сервер занят». */
const САЙТ_ИГРЫ = 'https://aleustim-boop.github.io';
const СВОЙ_КОМПЬЮТЕР = /^https?:\/\/(localhost|127\.0\.0\.1)(:\d+)?$/;

/** Убрать хвостовой слэш и разницу в регистре: адреса сравниваются точно. */
function привестиАдрес(адрес) {
  return String(адрес || '').trim().toLowerCase().replace(/\/+$/, '');
}

/* Запасной адрес на случай, если игру опубликуют в другом месте.
   Читается один раз при запуске из строки GAME_SERVER_ORIGIN в bot/.env,
   её может и не быть. */
const ЗАПАСНОЙ_АДРЕС = привестиАдрес(прочитатьНастройки().GAME_SERVER_ORIGIN);

/**
 * Можно ли отвечать этой странице.
 * Запроса не из браузера (там адреса-источника нет вовсе) это
 * не касается: правило существует только для браузеров.
 */
function источникРазрешён(источник, запасной) {
  if (!источник) return true;
  const адрес = привестиАдрес(источник);
  if (адрес === САЙТ_ИГРЫ) return true;

  // Второй довод нужен проверке: она подставляет свой запасной адрес,
  // не трогая настоящий файл настроек.
  const запас = запасной === undefined ? ЗАПАСНОЙ_АДРЕС : привестиАдрес(запасной);
  if (запас && адрес === запас) return true;

  return СВОЙ_КОМПЬЮТЕР.test(адрес);
}

/**
 * Заголовки ответа. Разрешение возвращаем не звёздочкой, а тем самым
 * адресом, который спрашивал, — так браузер пустит только его.
 */
function общиеЗаголовки(источник) {
  const заголовки = {
    'Content-Type': 'application/json; charset=utf-8',
    'Cache-Control': 'no-store',
    'Vary': 'Origin'
  };
  if (источник) {
    заголовки['Access-Control-Allow-Origin'] = источник;
    заголовки['Access-Control-Allow-Methods'] = 'GET, POST, OPTIONS';
    заголовки['Access-Control-Allow-Headers'] = 'Content-Type';
    заголовки['Access-Control-Max-Age'] = '86400';
  }
  return заголовки;
}

function ответить(ответ, код, тело) {
  if (ответ.writableEnded) return;
  // Адрес спросившего кладём на сам ответ в начале обработки —
  // так его не нужно таскать через все функции.
  ответ.writeHead(код, общиеЗаголовки(ответ.адресСтраницы));
  ответ.end(JSON.stringify(тело));
}

function ошибка(ответ, код, причина) {
  ответить(ответ, код, { ошибка: причина });
}

/** Прочитать тело запроса и разобрать как JSON. Пустое тело — пустой объект. */
function прочитатьТело(запрос) {
  return new Promise(function (готово, неудача) {
    let куски = '';
    let слишкомБольшое = false;

    запрос.on('data', function (кусок) {
      if (слишкомБольшое) return;
      куски += кусок;
      if (куски.length > МАКСИМУМ_ТЕЛА) {
        слишкомБольшое = true;
        неудача(new Error('слишком большой запрос'));
      }
    });

    запрос.on('end', function () {
      if (слишкомБольшое) return;
      if (!куски.trim()) return готово({});
      try {
        const разобранное = JSON.parse(куски);
        готово(разобранное && typeof разобранное === 'object' ? разобранное : {});
      } catch (сбой) {
        неудача(new Error('это не JSON'));
      }
    });

    запрос.on('error', неудача);
  });
}

/* ---------------------------------------------------------------------
   Обработка запросов
   --------------------------------------------------------------------- */

/**
 * Найти игрока по коду и пропуску из тела запроса.
 * Не нашли — значит, комнаты уже нет или пропуск чужой.
 */
function узнатьИгрока(тело, ответ) {
  const я = комнаты.найтиИгрока(тело.код, тело.пропуск);
  if (!я) {
    ошибка(ответ, 404, 'Комната не найдена или пропуск не подходит');
    return null;
  }
  return я;
}

/**
 * Создать комнату. Первый вид комнаты берём прямо из ответа комнат:
 * если спросить его отдельно, через найтиИгрока, комната тут же
 * пометится как «у неё спрашивали новости» — а по этой пометке
 * отличают живую игру от комнаты, созданной скриптом и брошенной.
 */
function создать(запрос, ответ) {
  const комната = комнаты.создатьКомнату(адресГостя(запрос));
  if (!комната.ок) return ошибка(ответ, 503, комната.причина);

  ответить(ответ, 200, {
    код: комната.код,
    пропуск: комната.пропуск,
    состояние: комната.состояние
  });
}

/**
 * Следить, не оборвалась ли связь с тем, кто спрашивал.
 * Возвращает функцию «его уже нет».
 *
 * То же самое делает длинный опрос ниже: если соединение закрылось
 * раньше, чем мы успели ответить, значит, человек ушёл. Разница в том,
 * что там мы снимаем игрока с ожидания, а здесь — не даём засчитать
 * вход тому, кто ответа уже не получит.
 */
function следитьЗаОбрывом(запрос, ответ) {
  let ушёл = false;
  запрос.on('close', function () {
    /* Осторожно: «close» на самом запросе приходит и у живого гостя —
       сразу, как только дочитано тело. Поэтому одного этого события мало,
       спрашиваем ещё и соединение: если оно уничтожено, а ответ не ушёл —
       человек нас точно не дождался. */
    if (!ответ.writableEnded && живогоСоединенияНет(запрос)) ушёл = true;
  });
  return function () { return ушёл || живогоСоединенияНет(запрос); };
}

/** Соединение с гостем уже разорвано? */
function живогоСоединенияНет(запрос) {
  return Boolean(запрос.socket && запрос.socket.destroyed);
}

async function войти(тело, запрос, ответ) {
  const адрес = адресГостя(запрос);
  const оборвалось = следитьЗаОбрывом(запрос, ответ);

  /* Сначала задержка шлагбаума, и только потом разбор кода: иначе
     подбор кодов шёл бы полным ходом, пока мы отвечаем мгновенно. */
  const очередь = await шлагбаум.пропустить(адрес);
  if (!очередь.можно) return ошибка(ответ, 429, очередь.причина);

  /* Пока держали паузу, игрок мог не дождаться и закрыть соединение
     (браузер игры ждёт десять секунд). Занимать за него место в комнате
     нельзя: он про это не узнает, а комната закроется на призрака. */
  if (оборвалось()) return;

  const вход = комнаты.войтиВКомнату(тело.код);
  if (!вход.ок) {
    /* Неудачей считаем только код, которого никогда не было, — это и есть
       подбор. Пустое поле и «там уже играют двое» бывают у живых людей
       сплошь и рядом: на телефоне палец легко нажимает «Войти» дважды.
       Устаревший код (комната была, но её убрали) тоже не в счёт: человек
       набрал ровно то, что ему продиктовали, и виноват в этом не он. */
    if (вход.кодНеПодошёл) шлагбаум.записатьНеудачу(адрес);
    return ошибка(ответ, 403, вход.причина);
  }

  // Место заняли, но получить ответ уже некому — отдаём место обратно.
  if (оборвалось()) {
    комнаты.отменитьВход(вход.код, вход.пропуск);
    return;
  }

  /* Прошлые промахи адресу тут не прощаются, и это нарочно: прощение
     при удачном входе оказалось дырой размером во всю защиту (подробно
     об этом — в шлагбаум.js, пункт 4). Живому человеку оно и не нужно:
     первые пять промахов и так бесплатны, а забываются они по одному
     в секунду — быстрее, чем человек успевает набрать код заново. */

  // Вид комнаты берём из ответа комнат — по той же причине, что и в «создать».
  ответить(ответ, 200, {
    код: вход.код,
    пропуск: вход.пропуск,
    состояние: вход.состояние
  });
}

function состояние(тело, ответ) {
  const я = узнатьИгрока(тело, ответ);
  if (!я) return;
  ответить(ответ, 200, { состояние: комнаты.показатьИгроку(я.комната, я.ктоЯ) });
}

function ход(тело, ответ) {
  const я = узнатьИгрока(тело, ответ);
  if (!я) return;

  const результат = комнаты.сделатьХод(я.комната, я.ктоЯ, тело);
  ответить(ответ, 200, {
    принято: результат.принято,
    причина: результат.принято ? null : результат.причина,
    состояние: комнаты.показатьИгроку(я.комната, я.ктоЯ)
  });
}

/**
 * Длинный опрос. Ответ уходит, когда в комнате что-то произошло,
 * либо когда истекло время ожидания — тогда клиент просто спросит снова.
 */
function чтоНового(тело, запрос, ответ) {
  const я = узнатьИгрока(тело, ответ);
  if (!я) return;

  const перестатьЖдать = комнаты.ждатьНовостей(
    я.комната, я.ктоЯ, тело.версия, ДЛИТЕЛЬНОСТЬ_ОПРОСА,
    function (вид) {
      if (вид) return ответить(ответ, 200, { изменилось: true, состояние: вид });
      // Пришли ни с чем: либо вышло время, либо комнату уже убрали.
      const жива = комнаты.найтиИгрока(тело.код, тело.пропуск);
      ответить(ответ, 200, жива ? { изменилось: false } : { изменилось: false, комнатыНет: true });
    }
  );

  /* Игрок закрыл вкладку или потерял сеть — снимаем его с ожидания.
     Это же и самый быстрый способ узнать о пропаже: если соединение
     закрылось раньше, чем мы успели ответить, значит человек ушёл,
     и соперник должен увидеть это сразу, а не через десяток секунд. */
  запрос.on('close', function () {
    перестатьЖдать(!ответ.writableEnded);
  });
}

function выйти(тело, ответ) {
  const я = узнатьИгрока(тело, ответ);
  if (!я) return;
  комнаты.выйти(я.комната, я.ктоЯ);
  ответить(ответ, 200, { вышел: true });
}

/**
 * Откуда пришёл запрос. Нужно только для счёта неудачных попыток входа;
 * никуда не записывается и не показывается. За туннелем у всех гостей
 * адрес может оказаться одинаковым — на этот случай шлагбаум считает
 * ещё и общее число неудач по серверу.
 */
function адресГостя(запрос) {
  return (запрос.socket && запрос.socket.remoteAddress) || 'неизвестно';
}

/** Разбор адреса запроса: русские названия приходят закодированными. */
function путьЗапроса(запрос) {
  const адрес = new URL(запрос.url, 'http://localhost');
  try {
    return decodeURIComponent(адрес.pathname);
  } catch (сбой) {
    return адрес.pathname;
  }
}

async function обработать(запрос, ответ) {
  const путь = путьЗапроса(запрос);
  const источник = запрос.headers.origin;

  if (!источникРазрешён(источник)) {
    // Посторонний сайт: отвечаем отказом и не даём разрешающих
    // заголовков — браузер не покажет ему ответ.
    ответ.адресСтраницы = null;
    return ошибка(ответ, 403, 'Этому сайту сервер игры не отвечает');
  }
  ответ.адресСтраницы = источник || null;

  // Браузер сначала спрашивает разрешения на запрос с чужого адреса.
  if (запрос.method === 'OPTIONS') {
    ответ.writeHead(204, общиеЗаголовки(ответ.адресСтраницы));
    return ответ.end();
  }

  if (запрос.method === 'GET' && (путь === '/здоровье' || путь === '/')) {
    return ответить(ответ, 200, { живой: true, комнат: комнаты.сколькоКомнат() });
  }

  if (запрос.method !== 'POST') {
    return ошибка(ответ, 405, 'Такой запрос сервер не принимает');
  }

  let тело;
  try {
    тело = await прочитатьТело(запрос);
  } catch (сбой) {
    return ошибка(ответ, 400, 'Запрос не понят: ' + сбой.message);
  }

  switch (путь) {
    case '/создать':    return создать(запрос, ответ);
    case '/войти':      return войти(тело, запрос, ответ);
    case '/состояние':  return состояние(тело, ответ);
    case '/что-нового': return чтоНового(тело, запрос, ответ);
    case '/ход':        return ход(тело, ответ);
    case '/выйти':      return выйти(тело, ответ);
    default:            return ошибка(ответ, 404, 'Такого адреса на сервере нет');
  }
}

