/**
 * Настройки берём из того же файла, что и бот — bot/.env.
 * Файла может не быть вовсе: тогда работаем на порту по умолчанию.
 * Ничего, кроме нужной строки, отсюда не читаем и никуда не выводим —
 * в этом файле лежит токен бота.
 */
function прочитатьНастройки(другойФайл) {
  const файл = другойФайл || path.join(__dirname, '..', 'bot', '.env');
  const настройки = Object.create(null);
  let текст = '';
  try {
    текст = fs.readFileSync(файл, 'utf8');
  } catch (ошибка) {
    return настройки;   // файла нет — это не беда
  }
  for (const строка of текст.split(/\r?\n/)) {
    const обрезанная = строка.trim();
    if (!обрезанная || обрезанная.startsWith('#')) continue;
    const знак = обрезанная.indexOf('=');
    if (знак === -1) continue;
    настройки[обрезанная.slice(0, знак).trim()] = обрезанная.slice(знак + 1).trim();
  }
  return настройки;
}

/** Похоже ли это на настоящий номер порта. */
function номерПортаГодится(число) {
  return Number.isInteger(число) && число > 0 && число < 65536;
}

/**
 * Откуда берём порт, по порядку:
 *   1) номер, написанный при запуске: node server/сервер.js 8790;
 *   2) строка GAME_SERVER_PORT в файле bot/.env;
 *   3) 8765 — если ничего не указано.
 *
 * Номер при запуске стоит первым нарочно: если привычный порт занят
 * чем-то посторонним, человек должен иметь возможность взять другой,
 * не открывая файл с токеном бота.
 */
function выбратьПорт(изКоманднойСтроки) {
  if (изКоманднойСтроки !== undefined && изКоманднойСтроки !== null && изКоманднойСтроки !== '') {
    const указанный = Number(изКоманднойСтроки);
    if (!номерПортаГодится(указанный)) {
      console.error('Не понял номер порта: «' + изКоманднойСтроки + '».');
      console.error('Нужно целое число от 1 до 65535, например: node server/сервер.js 8790');
      process.exit(1);
    }
    return указанный;
  }

  const изФайла = Number(прочитатьНастройки().GAME_SERVER_PORT);
  if (номерПортаГодится(изФайла)) return изФайла;
  return ПОРТ_ПО_УМОЛЧАНИЮ;
}

/**
 * Разобрать то, что человек написал после имени файла.
 *
 * Понимаем два способа, чтобы не заставлять запоминать один:
 *   node server/сервер.js 8790 4          два числа: порт, потом секунды;
 *   node server/сервер.js --опрос=4       словом, тогда порядок не важен
 *                                         (годится и --poll=4, и --порт=8790).
 *
 * Возвращаем то, что нашли, как есть — проверкой значений занимаются
 * выбратьПорт и выбратьДлительностьОпроса, каждая по-своему.
 */
function разобратьАргументы(аргументы) {
  const список = Array.isArray(аргументы) ? аргументы : [];
  const итог = { порт: undefined, опрос: undefined, безПамяти: false };
  const простыеЧисла = [];

  for (let i = 0; i < список.length; i++) {
    const кусок = String(список[i] === undefined || список[i] === null ? '' : список[i]).trim();
    if (!кусок) continue;

    /* «--без-памяти»: сервер для проверок. Знакомых и статистику считает
       в памяти, а на диск не пишет — иначе каждый прогон тестировщика
       дописывал бы владельцу выдуманные партии в настоящую статистику. */
    if (/^-{0,2}(без-памяти|no-memory)$/i.test(кусок)) {
      итог.безПамяти = true;
      continue;
    }

    // Значение может стоять и через знак равенства, и через пробел.
    const названо = кусок.match(/^-{0,2}(опрос|poll|порт|port)(?:[=:](.*))?$/i);
    if (названо) {
      const имя = названо[1].toLowerCase();
      let значение = названо[2];
      if (значение === undefined || значение === '') {
        значение = список[i + 1];
        i++;
      }
      if (имя === 'опрос' || имя === 'poll') итог.опрос = значение;
      else итог.порт = значение;
      continue;
    }

    простыеЧисла.push(кусок);
  }

  // Первое число без имени — порт, второе — секунды опроса.
  if (итог.порт === undefined && простыеЧисла.length > 0) итог.порт = простыеЧисла[0];
  if (итог.опрос === undefined && простыеЧисла.length > 1) итог.опрос = простыеЧисла[1];
  return итог;
}

/**
 * Сколько секунд держать ответ на «что нового». Порядок тот же, что у порта:
 *   1) сказанное при запуске: node server/сервер.js 8790 4;
 *   2) строка GAME_POLL_SECONDS в файле bot/.env;
 *   3) 25 секунд.
 *
 * Непонятное или несуразное значение сервер не считает поводом не запускаться:
 * человек чинит зависшую партию, а не настраивает программу. Поэтому
 * говорим вслух, что не поняли, и работаем с обычными 25 секундами.
 */
function выбратьДлительностьОпроса(изКоманднойСтроки, изФайла) {
  const откудаФайл = изФайла === undefined ? прочитатьНастройки().GAME_POLL_SECONDS : изФайла;

  const сказано = [
    { значение: изКоманднойСтроки, откуда: 'при запуске' },
    { значение: откудаФайл, откуда: 'в строке GAME_POLL_SECONDS файла bot/.env' }
  ];

  for (const попытка of сказано) {
    if (попытка.значение === undefined || попытка.значение === null || String(попытка.значение).trim() === '') {
      continue;
    }
    const секунд = Number(String(попытка.значение).trim().replace(',', '.'));
    const миллисекунд = Math.round(секунд * 1000);

    if (!Number.isFinite(секунд) || миллисекунд < САМЫЙ_КОРОТКИЙ_ОПРОС || миллисекунд > САМЫЙ_ДЛИННЫЙ_ОПРОС) {
      console.error('Не понял, сколько секунд держать опрос: «' + попытка.значение + '» (' + попытка.откуда + ').');
      console.error('Нужно число от ' + САМЫЙ_КОРОТКИЙ_ОПРОС / 1000 + ' до ' + САМЫЙ_ДЛИННЫЙ_ОПРОС / 1000 +
        ', например: node server/сервер.js 8790 4');
      console.error('Беру обычные ' + ОПРОС_ПО_УМОЛЧАНИЮ / 1000 + ' секунд.');
      return ОПРОС_ПО_УМОЛЧАНИЮ;
    }
    return миллисекунд;
  }

  return ОПРОС_ПО_УМОЛЧАНИЮ;
}

