/* =====================================================================
   Сервер игры вдвоём. Запускается на домашнем компьютере:

       node server/сервер.js            порт 8765
       node server/сервер.js 8790       если 8765 занят
       node server/сервер.js 8790 4     то же, но ответа ждём не 25 секунд, а 4
       node server/сервер.js 8799 --без-памяти
                                        сервер для проверок: знакомых и статистику
                                        считает, но на диск не пишет

   Ничего, кроме самого Node, не нужно: ни библиотек, ни базы данных.

   Почему длинные опросы, а не постоянное соединение (WebSocket):
   «Дурак» — игра ходовая, задержка в полсекунды незаметна, а постоянное
   соединение пришлось бы писать руками. Здесь всё проще: клиент
   спрашивает «что нового», сервер придерживает ответ до события
   или до конца отведённого времени и отвечает.

   Зачем второе число при запуске (длительность опроса). Между игроком
   и этим сервером обычно стоит туннель — чужая программа, которая даёт
   домашнему компьютеру адрес в интернете. Некоторые туннели не терпят
   долгих молчаливых соединений и рвут их: serveo, например, обрывает
   ожидание примерно на пятой секунде и отвечает игре ошибкой 502.
   Для браузера это выглядит как сбой, а для человека — как зависшая
   партия: ход соперника не приходит вовсе. Лекарство простое — держать
   ответ меньше, чем туннель терпит: тогда сервер успевает ответить сам,
   а игра тут же спрашивает снова. Отсюда и настройка: 25 секунд хороши
   для прямого доступа (меньше пустых запросов), 3–5 секунд спасают
   партию за нетерпеливым туннелем.

   Что умеет сервер (все ответы — JSON):

     GET  /здоровье     жив ли сервер и сколько сейчас комнат
     GET  /статистика   счётчики партий за сегодня, 7 и 30 дней (для бота)
     POST /раздача-дня  { initData, день, исход, ходов } → записать свой итог
                        раздачи дня и получить сводку; без исхода — только сводка
     GET  /раздача-дня?день=2026-09-07   та же сводка, для просмотра
     POST /создать      создать комнату      → { код, пропуск, состояние }
                        от бота: { безХозяина: true, пропускБота, мест }
                                             → { код, безХозяина: true, ждётСекунд }
     GET  /стол?код=XXXX  жив ли стол (для бота): { есть, этап, людей, мест,
                        ждётЕщёСекунд } или { есть: false, закрылся }
     POST /войти        { код, имя }         → { пропуск, состояние }
     POST /состояние    { код, пропуск }     → состояние прямо сейчас
     POST /что-нового   { код, пропуск, версия } → ответ придёт по событию
     POST /ход          { код, пропуск, действие, карта, пара }
     POST /выйти        { код, пропуск }
     POST /знакомые     { initData }         → с кем этот человек играл
                                               и кто из них сейчас за столом

   Действия в запросе /ход: 'ходить' (карта), 'отбить' (пара, карта),
   'беру', 'бито' и 'ещё' — предложить сыграть ещё партию, когда
   предыдущая закончилась.

   Стол на компанию собирается прямо при создании: в теле /создать можно
   прислать { мест, переводной, парами, уровеньБотов, имя } — все поля
   необязательные. Например, четверо парами в переводного:

       { "мест": 4, "парами": true, "переводной": true, "имя": "Аня" }

   Пустое тело — прежняя комната на двоих, которая раздаёт карты сама,
   как только вошёл друг. Настройки можно и поменять потом, уже созданной
   комнате, запросом /ход с действием 'настройки' — этот путь работает
   как работал. Ничего из присланного сервер здесь не разбирает: годность
   значений проверяют комнаты (см. применитьНастройки в комнаты.js).

   Настройки (все необязательные, лежат в bot/.env рядом с настройками бота):
     GAME_SERVER_PORT    порт, если не подходит 8765;
     GAME_SERVER_ORIGIN  ещё один адрес страницы, которой разрешено
                         обращаться к серверу, — на случай публикации
                         игры в новом месте;
     GAME_POLL_SECONDS   сколько секунд держать ответ на «что нового»
                         (от 1 до 60, по умолчанию 25). То же самое можно
                         сказать при запуске вторым числом — так быстрее,
                         файл открывать не нужно.

   Пропуск — секретный ключ игрока, его выдают при создании комнаты
   или при входе. Он нужен в каждом запросе: по нему игрок возвращается
   в свою партию после обрыва связи, и он же не даёт ходить за соперника.

   Правила игры сервер не выдумывает: они лежат в js/game.js — там же,
   откуда их берёт браузер. Клиенту верить нельзя, поэтому каждый ход
   проверяется здесь заново.
   ===================================================================== */

