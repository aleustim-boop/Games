/* Сколько держим запрос «что нового» без событий. Меньше минуты —
   чтобы промежуточные железки в сети не рвали соединение молча. */
const ОПРОС_ПО_УМОЛЧАНИЮ = 25 * 1000;

/* Границы разумного. Меньше секунды — сервер и сеть загружены впустую:
   игра будет спрашивать по нескольку раз в секунду ни о чём. Больше
   минуты — почти любой посредник в сети успеет счесть соединение
   брошенным и оборвать его. */
const САМЫЙ_КОРОТКИЙ_ОПРОС = 1 * 1000;
const САМЫЙ_ДЛИННЫЙ_ОПРОС = 60 * 1000;

/* Не константа нарочно: значение выбирается при запуске (см. шапку файла).
   Всё остальное в сервере смотрит только сюда, чтобы длительность
   нигде не разошлась сама с собой. */
let длительностьОпроса = ОПРОС_ПО_УМОЛЧАНИЮ;

/* Больше этого тело запроса быть не может: там всегда пара чисел
   и короткий код. Ограничение — от мусора и от случайной заливки. */
const МАКСИМУМ_ТЕЛА = 4 * 1024;

const ПОРТ_ПО_УМОЛЧАНИЮ = 8765;

