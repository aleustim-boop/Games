/* Откуда игре разрешено обращаться к серверу.

   Страница игры и сервер живут на разных адресах, поэтому браузер
   спрашивает у сервера разрешения. Раньше здесь стояла звёздочка —
   «пускаем всех», и любой сайт мог бы дёргать сервер игры у человека,
   который просто открыл этот сайт. Поэтому круг сужен до двух:
     — опубликованная игра;
     — свой же компьютер (нужно для проверок и игры без интернета).

   Чего этот список НЕ делает. Он не защищает сервер от программ: заголовок
   «Origin» шлёт только браузер, а запрос из скрипта его не шлёт вовсе
   и проходит свободно (см. источникРазрешён ниже). Список — правило
   для чужих страниц, не для чужих программ.

   От программы, которая в цикле создаёт комнаты, полной защиты нет
   ни здесь, ни где-либо ещё: сервер не умеет отличать скрипт от человека.
   Есть только смягчение — потеснитьЖадного в комнаты.js. Когда мест
   не хватает, сервер отбирает место не у первого попавшегося, а у того
   адреса, который держит больше всех забытых комнат: тех, где не сделали
   ни одного хода и о которых давно никто не спрашивал. Живому игроку это
   даёт шанс войти, но пока забытые комнаты не состарились (полминуты),
   он всё равно услышит «сервер занят». */
const САЙТ_ИГРЫ = 'https://aleustim-boop.github.io';
const СВОЙ_КОМПЬЮТЕР = /^https?:\/\/(localhost|127\.0\.0\.1)(:\d+)?$/;

/** Убрать хвостовой слэш и разницу в регистре: адреса сравниваются точно. */
function привестиАдрес(адрес) {
  return String(адрес || '').trim().toLowerCase().replace(/\/+$/, '');
}

/* Запасной адрес на случай, если игру опубликуют в другом месте.
   Читается один раз при запуске из строки GAME_SERVER_ORIGIN в bot/.env,
   её может и не быть. */
const ЗАПАСНОЙ_АДРЕС = привестиАдрес(прочитатьНастройки().GAME_SERVER_ORIGIN);

/**
 * Можно ли отвечать этой странице.
 * Запроса не из браузера (там адреса-источника нет вовсе) это
 * не касается: правило существует только для браузеров.
 */
function источникРазрешён(источник, запасной) {
  if (!источник) return true;
  const адрес = привестиАдрес(источник);
  if (адрес === САЙТ_ИГРЫ) return true;

  // Второй довод нужен проверке: она подставляет свой запасной адрес,
  // не трогая настоящий файл настроек.
  const запас = запасной === undefined ? ЗАПАСНОЙ_АДРЕС : привестиАдрес(запасной);
  if (запас && адрес === запас) return true;

  return СВОЙ_КОМПЬЮТЕР.test(адрес);
}

/**
 * Заголовки ответа. Разрешение возвращаем не звёздочкой, а тем самым
 * адресом, который спрашивал, — так браузер пустит только его.
 */
function общиеЗаголовки(источник) {
  const заголовки = {
    'Content-Type': 'application/json; charset=utf-8',
    'Cache-Control': 'no-store',
    'Vary': 'Origin'
  };
  if (источник) {
    заголовки['Access-Control-Allow-Origin'] = источник;
    заголовки['Access-Control-Allow-Methods'] = 'GET, POST, OPTIONS';
    /* Какие заголовки странице разрешено присылать. Звёздочку не ставим
       нарочно — перечисляем поимённо, чтобы разрешение оставалось узким.

       Content-Type       — в нём игра говорит, что шлёт JSON;
       bypass-tunnel-reminder — пропуск через бесплатный туннель: без него
         туннель loca.lt показывает игре свою страницу-предупреждение
         вместо ответа сервера (отказ 511), и партия не начинается вовсе.
         Сервер этот заголовок не читает и никак на него не смотрит —
         он нужен туннелю по дороге. Но назвать его здесь обязательно:
         на необычный заголовок браузер сначала спрашивает разрешения
         отдельным запросом OPTIONS и, не найдя заголовок в этом списке,
         отменяет запрос целиком, даже не отправив его. */
    заголовки['Access-Control-Allow-Headers'] = 'Content-Type, bypass-tunnel-reminder';
    заголовки['Access-Control-Max-Age'] = '86400';
  }
  return заголовки;
}

function ответить(ответ, код, тело) {
  if (ответ.writableEnded) return;
  // Адрес спросившего кладём на сам ответ в начале обработки —
  // так его не нужно таскать через все функции.
  ответ.writeHead(код, общиеЗаголовки(ответ.адресСтраницы));
  ответ.end(JSON.stringify(тело));
}

function ошибка(ответ, код, причина) {
  ответить(ответ, код, { ошибка: причина });
}

/** Прочитать тело запроса и разобрать как JSON. Пустое тело — пустой объект. */
function прочитатьТело(запрос) {
  return new Promise(function (готово, неудача) {
    let куски = '';
    let слишкомБольшое = false;

    запрос.on('data', function (кусок) {
      if (слишкомБольшое) return;
      куски += кусок;
      if (куски.length > МАКСИМУМ_ТЕЛА) {
        слишкомБольшое = true;
        неудача(new Error('слишком большой запрос'));
      }
    });

    запрос.on('end', function () {
      if (слишкомБольшое) return;
      if (!куски.trim()) return готово({});
      try {
        const разобранное = JSON.parse(куски);
        готово(разобранное && typeof разобранное === 'object' ? разобранное : {});
      } catch (сбой) {
        неудача(new Error('это не JSON'));
      }
    });

    запрос.on('error', неудача);
  });
}

