/**
 * Один-единственный признак, который сервер добавляет к отказу «вас
 * в этой комнате нет»: место человека заняли, пока его не было.
 *
 * Зачем. Отказ был один на два совсем разных случая: комнаты нет вовсе —
 * и комната жива, но место освободили, пока человек молчал (телефон уснул,
 * а стол потом пересобрали). Сказать надо разное: в первом случае «игра
 * закрылась, создайте новую», во втором «вас долго не было, место заняли —
 * попросите у друга код и войдите заново». Страница различить не могла:
 * оба ответа совпадали знак в знак.
 *
 * Признак достаётся ТОЛЬКО тому, чей пропуск комната помнит (ждётЛиОбратно
 * в комнаты.js). Перебирающему коды он не достаётся никогда, и это главное
 * условие: шлагбаум стоит лишь на двери «войти», а здесь его нет вовсе.
 * Замер до правки: около 3500 кодов в секунду на этой двери против одного
 * на входе — признак «такая комната есть» для всех подряд отменил бы
 * защиту, ради которой шлагбаум и написан.
 *
 * Наружу отсюда выходит ровно один бит: ни числа игроков, ни этапа,
 * ни имён в нём нет и взяться им неоткуда.
 */
function местоЧеловекаЗаняли(тело) {
  return комнаты.ждётЛиОбратно(тело.код, тело.пропуск);
}

/**
 * Найти игрока по коду и пропуску из тела запроса.
 * Не нашли — значит, комнаты уже нет, место заняли или пропуск чужой.
 */
function узнатьИгрока(тело, ответ) {
  const я = комнаты.найтиИгрока(тело.код, тело.пропуск);
  if (!я) {
    /* Тело отказа собираем здесь поле за полем: слово об ошибке — прежнее,
       и к нему, если место человека и правда заняли, ровно один признак.
       Старая страница читает у отказа только номер 404 и слово «ошибка»,
       поэтому лишнего поля она не замечает вовсе. */
    const отказ = { ошибка: 'Комната не найдена или пропуск не подходит' };
    if (местоЧеловекаЗаняли(тело)) отказ.местоЗаняли = true;
    ответить(ответ, 404, отказ);
    return null;
  }
  return я;
}

/**
 * Создать комнату. Первый вид комнаты берём прямо из ответа комнат:
 * если спросить его отдельно, через найтиИгрока, комната тут же
 * пометится как «у неё спрашивали новости» — а по этой пометке
 * отличают живую игру от комнаты, созданной скриптом и брошенной.
 *
 * Тело запроса отдаём комнатам целиком: там из него берут настройки
 * стола — сколько мест, переводной ли, парами ли, каким соперником
 * играют боты и как звать создателя. Разбирать их здесь незачем и вредно:
 * пусть проверка значений живёт в одном месте (комнаты.js), иначе две
 * половины однажды разойдутся в том, что считать допустимым.
 * Тело пустое — получится прежняя комната на двоих, как было всегда.
 */
/* Имена людей из подписи Telegram — только для писем ленты бота: номер →
   имя, в памяти процесса, без диска. Потолок нужен, чтобы память не росла
   на людном сервере; вытесняем самых давних (Map помнит порядок записи). */
const ИМЁН_ИЗ_ПОДПИСИ_ПОМНИМ = 2000;
const имяИзПодписиПоНомеру = new Map();

/** Запомнить имя из уже проверенной подписи. Нет номера — нечего и помнить. */
function запомнитьИмяИзПодписи(номер, initData) {
  if (!номер) return;
  const имя = имяДляПисьма(initData);
  имяИзПодписиПоНомеру.delete(номер);   // свежая запись встаёт в конец очереди
  if (!имя) return;
  имяИзПодписиПоНомеру.set(номер, имя);
  if (имяИзПодписиПоНомеру.size > ИМЁН_ИЗ_ПОДПИСИ_ПОМНИМ) {
    имяИзПодписиПоНомеру.delete(имяИзПодписиПоНомеру.keys().next().value);
  }
}

/**
 * Вписать в тело запроса номер игрока в Telegram — тот, что удостоверен
 * подписью. Делать это надо ОБЯЗАТЕЛЬНО и всегда, даже когда подписи нет:
 * поле перезаписывается, поэтому прислать себе чужой номер снаружи
 * невозможно. Если бы мы просто «дополняли» тело, клиент подставил бы
 * любой номер сам и завёл бы знакомство от чужого имени.
 */
function отметитьКтоЭто(тело) {
  const целое = тело && typeof тело === 'object' ? тело : {};
  целое.телеграм = ктоПрислал(целое.initData);
  /* Имя для писем ленты берём здесь, пока подпись ещё при нас: в письмо
     идёт имя, которое назвал Telegram, а не то, что человек набрал в игре. */
  запомнитьИмяИзПодписи(целое.телеграм, целое.initData);
  /* Подпись дальше не нужна никому: комнаты про Telegram ничего не знают,
     и таскать её по всему серверу незачем. */
  delete целое.initData;
  /* Ссылку за стол при создании и входе не берём никогда: её присылает
     только хозяин в «что нового», и там её проверяют (см. ссылкаДляПисьма).
     Убираем поле, чтобы комнаты не получили его ни по какой дороге. */
  delete целое.ссылка;
  /* «Без хозяина» — просьба бота, и только его: поле перезаписывается
     по пропуску бота, из браузера оно не доходит. Сам пропуск дальше
     не нужен. */
  целое.безХозяина = целое.безХозяина === true && этоПропускБота(целое.пропускБота);
  delete целое.пропускБота;
  return целое;
}

function создать(тело, запрос, ответ) {
  const комната = комнаты.создатьКомнату(адресГостя(запрос), отметитьКтоЭто(тело));
  if (!комната.ок) return ошибка(ответ, 503, комната.причина);

  // Стол без хозяина: пропуска и состояния нет, боту — код и срок ожидания.
  if (комната.безХозяина) {
    return ответить(ответ, 200, { код: комната.код, безХозяина: true, ждётСекунд: комната.ждётСекунд });
  }
  ответить(ответ, 200, {
    код: комната.код,
    пропуск: комната.пропуск,
    состояние: комната.состояние
  });
}

/**
 * Что со столом — дверь для бота, который открыл стол из чата и сам за него
 * не садился. Ответ — одни числа (см. состояниеСтола).
 *
 * Почему здесь стоит шлагбаум, хотя дверь только читает. Ответ «такая
 * комната есть» — ровно то, что ищет перебирающий коды: их всего четыре
 * знака, и без задержки эту дверь можно опрашивать тысячи раз в секунду,
 * пока не найдётся чужой живой стол. Тот же довод записан у двери «войти»
 * и у признака «место заняли» — и здесь он ничем не слабее. Поэтому:
 * пауза до разбора кода и штраф за код, которого никогда не было.
 *
 * Своему боту это не мешает вовсе: он спрашивает про СВОЙ стол, а удачный
 * вопрос штрафа не даёт, и первые пять промахов и так прощаются.
 */
async function столДляБота(запрос, ответ) {
  const гость = адресГостя(запрос);
  const очередь = await шлагбаум.пропустить(гость);
  if (!очередь.можно) return ошибка(ответ, 429, очередь.причина);
  if (живогоСоединенияНет(запрос)) return;   // спрашивавший не дождался

  const адрес = new URL(запрос.url, 'http://localhost');
  const код = адрес.searchParams.get('код') || адрес.searchParams.get('code') || '';
  const стол = комнаты.состояниеСтола(код);

  /* Штрафуем только за код, которого никогда не было, — это и есть подбор.
     Закрывшийся стол не в счёт: бот спрашивал про свой, и то, что стол
     дожил до конца срока, — не его вина. */
  if (!стол.есть && !стол.закрылся) шлагбаум.записатьНеудачу(гость);
  return ответить(ответ, 200, стол);
}

/**
 * Следить, не оборвалась ли связь с тем, кто спрашивал.
 * Возвращает функцию «его уже нет».
 *
 * То же самое делает длинный опрос ниже: если соединение закрылось
 * раньше, чем мы успели ответить, значит, человек ушёл. Разница в том,
 * что там мы снимаем игрока с ожидания, а здесь — не даём засчитать
 * вход тому, кто ответа уже не получит.
 */
function следитьЗаОбрывом(запрос, ответ) {
  let ушёл = false;
  запрос.on('close', function () {
    /* Осторожно: «close» на самом запросе приходит и у живого гостя —
       сразу, как только дочитано тело. Поэтому одного этого события мало,
       спрашиваем ещё и соединение: если оно уничтожено, а ответ не ушёл —
       человек нас точно не дождался. */
    if (!ответ.writableEnded && живогоСоединенияНет(запрос)) ушёл = true;
  });
  return function () { return ушёл || живогоСоединенияНет(запрос); };
}

/** Соединение с гостем уже разорвано? */
function живогоСоединенияНет(запрос) {
  return Boolean(запрос.socket && запрос.socket.destroyed);
}

async function войти(тело, запрос, ответ) {
  const адрес = адресГостя(запрос);
  const оборвалось = следитьЗаОбрывом(запрос, ответ);

  /* Сначала задержка шлагбаума, и только потом разбор кода: иначе
     подбор кодов шёл бы полным ходом, пока мы отвечаем мгновенно. */
  const очередь = await шлагбаум.пропустить(адрес);
  if (!очередь.можно) return ошибка(ответ, 429, очередь.причина);

  /* Пока держали паузу, игрок мог не дождаться и закрыть соединение
     (браузер игры ждёт десять секунд). Занимать за него место в комнате
     нельзя: он про это не узнает, а комната закроется на призрака. */
  if (оборвалось()) return;

  /* Тело передаём целиком: комнаты возьмут из него имя, которым назвался
     вошедший. Не назвался — сядет за стол как «Игрок 3» по номеру места. */
  const вход = комнаты.войтиВКомнату(тело.код, отметитьКтоЭто(тело));
  if (!вход.ок) {
    /* Неудачей считаем только код, которого никогда не было, — это и есть
       подбор. Пустое поле и «там уже играют двое» бывают у живых людей
       сплошь и рядом: на телефоне палец легко нажимает «Войти» дважды.
       Устаревший код (комната была, но её убрали) тоже не в счёт: человек
       набрал ровно то, что ему продиктовали, и виноват в этом не он. */
    if (вход.кодНеПодошёл) шлагбаум.записатьНеудачу(адрес);
    return ошибка(ответ, 403, вход.причина);
  }

  // Место заняли, но получить ответ уже некому — отдаём место обратно.
  if (оборвалось()) {
    комнаты.отменитьВход(вход.код, вход.пропуск);
    return;
  }

  /* Прошлые промахи адресу тут не прощаются, и это нарочно: прощение
     при удачном входе оказалось дырой размером во всю защиту (подробно
     об этом — в шлагбаум.js, пункт 4). Живому человеку оно и не нужно:
     первые пять промахов и так бесплатны, а забываются они по одному
     в секунду — быстрее, чем человек успевает набрать код заново. */

  // Вид комнаты берём из ответа комнат — по той же причине, что и в «создать».
  ответить(ответ, 200, {
    код: вход.код,
    пропуск: вход.пропуск,
    состояние: вход.состояние
  });
}

function состояние(тело, ответ) {
  const я = узнатьИгрока(тело, ответ);
  if (!я) return;
  ответить(ответ, 200, { состояние: комнаты.показатьИгроку(я.комната, я.ктоЯ) });
}

function ход(тело, ответ) {
  const я = узнатьИгрока(тело, ответ);
  if (!я) return;

  const результат = комнаты.сделатьХод(я.комната, я.ктоЯ, тело);
  ответить(ответ, 200, {
    принято: результат.принято,
    причина: результат.принято ? null : результат.причина,
    состояние: комнаты.показатьИгроку(я.комната, я.ктоЯ)
  });
}

/**
 * Длинный опрос. Ответ уходит, когда в комнате что-то произошло,
 * либо когда истекло время ожидания — тогда клиент просто спросит снова.
 */
function чтоНового(тело, запрос, ответ) {
  const я = узнатьИгрока(тело, ответ);
  if (!я) return;

  /* Свёрнутая страница на Android часто опрашивает дальше, а человек стола
     не видит: признак от страницы говорит ленте, что письмо ему нужно. */
  комнаты.отметитьСкрытость(я.комната, я.ктоЯ, тело.скрыта === true);

  /* Ссылка за стол для кнопки «Открыть стол» принимается только здесь:
     человека узнали по пропуску, и комната возьмёт ссылку, только если он
     хозяин стола. Ничего не ждём — опрос не должен задерживаться. */
  принятьСсылкуЗаСтол(тело.ссылка, я, запрос);

  const перестатьЖдать = комнаты.ждатьНовостей(
    я.комната, я.ктоЯ, тело.версия, длительностьОпроса,
    function (вид) {
      if (вид) return ответить(ответ, 200, { изменилось: true, состояние: вид });
      // Пришли ни с чем: либо вышло время, либо комнату уже убрали.
      const жива = комнаты.найтиИгрока(тело.код, тело.пропуск);
      if (жива) return ответить(ответ, 200, { изменилось: false });
      /* Второй выход той же двери. Признак ставится и здесь — по тому же
         правилу и той же проверкой: разойдись эти два места, страница
         получала бы разные слова об одной и той же беде, смотря какой
         запрос успел первым. Такое ищут неделями. */
      const конец = { изменилось: false, комнатыНет: true };
      if (местоЧеловекаЗаняли(тело)) конец.местоЗаняли = true;
      ответить(ответ, 200, конец);
    }
  );

  /* Игрок закрыл вкладку или потерял сеть — снимаем его с ожидания.
     Слушаем «close» именно на ОТВЕТЕ, а не на запросе: у запроса это
     событие срабатывает сразу, как только дочитано тело (даже у живого
     гостя), и ничего не говорит о реальном разрыве. У ответа же, пока мы
     держим долгий опрос и ничего не отправили, «close» приходит ровно
     в момент, когда соединение и правда оборвалось — тогда writableEnded
     ещё false. Если же мы сами уже ответили (ответить() вызвал end()),
     writableEnded к этому моменту true, и это не обрыв, а обычный конец
     ожидания — перестатьЖдать(false) в таком случае безвреден. */
  ответ.on('close', function () {
    перестатьЖдать(!ответ.writableEnded);
  });
}

function выйти(тело, ответ) {
  const я = узнатьИгрока(тело, ответ);
  if (!я) return;
  комнаты.выйти(я.комната, я.ктоЯ);
  ответить(ответ, 200, { вышел: true });
}

/**
 * Откуда пришёл запрос. Нужно только для счёта неудачных попыток входа;
 * никуда не записывается и не показывается. За туннелем у всех гостей
 * адрес может оказаться одинаковым — на этот случай шлагбаум считает
 * ещё и общее число неудач по серверу.
 */
function адресГостя(запрос) {
  return (запрос.socket && запрос.socket.remoteAddress) || 'неизвестно';
}

/** Разбор адреса запроса: русские названия приходят закодированными. */
function путьЗапроса(запрос) {
  const адрес = new URL(запрос.url, 'http://localhost');
  try {
    return decodeURIComponent(адрес.pathname);
  } catch (сбой) {
    return адрес.pathname;
  }
}

async function обработать(запрос, ответ) {
  const путь = путьЗапроса(запрос);
  const источник = запрос.headers.origin;

  if (!источникРазрешён(источник)) {
    // Посторонний сайт: отвечаем отказом и не даём разрешающих
    // заголовков — браузер не покажет ему ответ.
    ответ.адресСтраницы = null;
    return ошибка(ответ, 403, 'Этому сайту сервер игры не отвечает');
  }
  ответ.адресСтраницы = источник || null;

  // Браузер сначала спрашивает разрешения на запрос с чужого адреса.
  if (запрос.method === 'OPTIONS') {
    ответ.writeHead(204, общиеЗаголовки(ответ.адресСтраницы));
    return ответ.end();
  }

  if (запрос.method === 'GET' && (путь === '/здоровье' || путь === '/')) {
    return ответить(ответ, 200, { живой: true, комнат: комнаты.сколькоКомнат(), коммит: КОММИТ_СЕРВЕРА });
  }

  /* Статистика партий — для бота, который складывает её со своей и
     показывает владельцу. Отдаём всем, кто спросит, и это решение, а не
     недосмотр: владельца сервер не знает, а в ответе одни счётчики —
     ни имён, ни номеров, ни кодов комнат (см. server/статистика.js). */
  if (запрос.method === 'GET' && путь === '/статистика') {
    return ответить(ответ, 200, статистика.отчёт());
  }

  // Сводка раздачи дня без записи — для бота и для просмотра глазами.
  if (запрос.method === 'GET' && путь === '/раздача-дня') {
    return сводкаРаздачиДня(запрос, ответ);
  }

  // Жив ли стол с таким кодом — для бота, открывшего стол без хозяина.
  if (запрос.method === 'GET' && путь === '/стол') {
    return столДляБота(запрос, ответ);
  }

  if (запрос.method !== 'POST') {
    return ошибка(ответ, 405, 'Такой запрос сервер не принимает');
  }

  let тело;
  try {
    тело = await прочитатьТело(запрос);
  } catch (сбой) {
    return ошибка(ответ, 400, 'Запрос не понят: ' + сбой.message);
  }

  switch (путь) {
    case '/приглашение': return приглашение(тело, ответ);
    case '/создать':    return создать(тело, запрос, ответ);
    case '/войти':      return войти(тело, запрос, ответ);
    case '/состояние':  return состояние(тело, ответ);
    case '/что-нового': return чтоНового(тело, запрос, ответ);
    case '/ход':        return ход(тело, ответ);
    case '/выйти':      return выйти(тело, ответ);
    case '/открытые-столы': return списокОткрытыхСтолов(тело, ответ);
    case '/сесть':      return сестьЗаСтол(тело, запрос, ответ);
    case '/знакомые':   return списокЗнакомых(тело, ответ);
    case '/позвать':    return позватьЗнакомого(тело, ответ);
    case '/не-звать':   return большеНеЗвать(тело, ответ);
    case '/рейтинг':    return таблицаРейтинга(тело, ответ);
    case '/раздача-дня': return раздачаДняИгрока(тело, ответ);
    case '/билет':      return выдатьБилет(тело, запрос, ответ);
    case '/итог-с-ботом': return итогСБотом(тело, запрос, ответ);
    case '/подбор':      return подборВстатьВОчередь(тело, ответ);
    case '/подбор-новости': return подборНовости(тело, запрос, ответ);
    case '/подбор-отмена': return подборОтмена(тело, ответ);
    default:            return ошибка(ответ, 404, 'Такого адреса на сервере нет');
  }
}

/* ---------------------------------------------------------------------
   Приглашение через Telegram: готовим сообщение, которое отправит игрок

   Зачем это нужно. Раньше «Позвать друга» открывало список чатов ссылкой
   t.me/share/url. На телефоне так можно, а на компьютере окно игры уходит
   за главное окно Telegram, и человек его не находит — владелец сказал
   про это прямо: «улетает, и я его не могу найти». Правильный способ есть:
   бот заранее готовит сообщение (savePreparedInlineMessage), а игра
   показывает выбор чата поверх себя (WebApp.shareMessage). Но звать
   Telegram может только тот, у кого есть токен бота, — а токен в браузер
   отдавать нельзя никогда. Поэтому посредником работает этот сервер.

   Про токен здесь три правила, и они важнее любого удобства:
     1) он читается из bot/.env один раз и живёт только в памяти процесса;
     2) он не попадает больше НИКУДА: ни в ответы, ни в записи в консоль,
        ни в тексты ошибок. Поэтому беды Telegram наружу не пересказываются
        вовсе — игре уходит короткое «не вышло», и она молча делает по-старому;
     3) нет файла или строки с токеном — сервер не падает и не ругается,
        а честно отвечает «не умею».

   Про «клиенту не верим». Кому готовить сообщение, решает не браузер:
   он присылает initData — строку, которую Telegram подписал ключом бота.
   Мы проверяем подпись и берём номер игрока ИЗ НЕЁ. Без этой проверки
   любой готовил бы сообщения от чужого имени.
   --------------------------------------------------------------------- */

/* Токен читаем один раз при запуске: трогать файл с секретом на каждый
   запрос незачем. */
const ТОКЕН_БОТА = (прочитатьНастройки().BOT_TOKEN || '').trim();

/* ---------- Оснастка для проверок ----------

   Одна-единственная щель во всём разговоре с Telegram, и она нужна вот
   почему. Всё, что сервер делает от имени бота, начинается с токена:
   без него не проверить подпись игрока и некому отправить письмо.
   Настоящего токена у проверок нет и быть не должно — значит, без этой
   щели проверить можно только отказы, а САМ ЗОВ («письмо ушло нужному
   человеку, текст такой, кнопки такие») не проверить вовсе.

   Поэтому проверка из tests/ подставляет сюда выдуманный токен и
   поддельную трубу — свой кусок кода вместо api.telegram.org. Делает
   она это в своём процессе: у каждого процесса свой экземпляр модуля,
   и на боевой сервер это не действует никак. По сети сюда не дотянуться:
   дверей к этой функции нет, её можно позвать только через require.

   Пока никто не подставил своего — здесь настоящий токен из bot/.env
   и настоящая труба, всё как было. */
let токенСейчас = ТОКЕН_БОТА;
let трубаСейчас = null;

/**
 * Поставить выдуманный токен и поддельную трубу (только для проверок).
 * Оба довода обязательны нарочно: выдуманный токен без поддельной трубы
 * означал бы настоящие запросы в Telegram с мусорным токеном.
 * Позвать без доводов — вернуть всё на место.
 */
function оснасткаДляПроверки(токен, спросить) {
  if (токен === undefined && спросить === undefined) {
    токенСейчас = ТОКЕН_БОТА;
    трубаСейчас = null;
    имяБотаВTelegram = '';
    последнийGetMe = 0;
    getMeИдёт = false;
    return true;
  }
  if (typeof токен !== 'string' || !токен || typeof спросить !== 'function') return false;
  токенСейчас = токен;
  трубаСейчас = спросить;
  имяБотаВTelegram = '';       // у выдуманного бота своё имя
  последнийGetMe = 0;          // и первый вопрос о нём — сразу, без паузы
  getMeИдёт = false;
  return true;
}

/** Умеет ли сервер говорить с Telegram. Наружу уходит только «да» или «нет». */
function умеемГотовитьПриглашения() {
  return токенСейчас.length > 0;
}

/* Пропуск бота — чем бот доказывает серверу, что это он, когда просит
   стол без хозяина. Отдельного секрета не заводим: у бота и сервера уже
   есть один общий — токен бота в bot/.env, — и пропуск считается из него
   у каждого на своей стороне: sha256 от строки «стол-из-чата:» + токен,
   шестнадцатеричными знаками. Сам токен по сети не ходит; по пропуску
   восстановить его нельзя. Токена нет — пропуска нет, и стол без хозяина
   не даётся никому. */
function пропускБотаИзТокена(токен) {
  if (typeof токен !== 'string' || !токен) return '';
  return crypto.createHash('sha256').update('стол-из-чата:' + токен, 'utf8').digest('hex');
}

/* Считаем при каждой проверке, а не раз при запуске: пропуск зависит
   от токена, а токен у проверки свой (см. оснасткаДляПроверки). Стоит
   это одну свёртку sha256 на редкий запрос — дешевле, чем вторая копия
   значения, которая однажды разойдётся с токеном. */
function пропускБотаСейчас() {
  return пропускБотаИзТокена(токенСейчас);
}

/** Это пропуск нашего бота? Сравнение за одинаковое время, как у подписи. */
function этоПропускБота(пропуск) {
  const ПРОПУСК_БОТА = пропускБотаСейчас();
  if (!ПРОПУСК_БОТА || typeof пропуск !== 'string') return false;
  const своё = Buffer.from(ПРОПУСК_БОТА, 'utf8');
  const чужое = Buffer.from(пропуск, 'utf8');
  return своё.length === чужое.length && crypto.timingSafeEqual(своё, чужое);
}

/* Сколько ждём ответа Telegram. Дольше держать нельзя: игра всё это время
   молчит человеку в лицо, а запасной путь у неё простой и быстрый. */
const ЖДЁМ_TELEGRAM = 5000;

/* Приглашение живёт минуты, и подпись старше суток для него бессмысленна. */
const ПОДПИСЬ_ГОДНА = 24 * 60 * 60 * 1000;

/**
 * Проверить подпись initData и вернуть номер игрока в Telegram.
 * Не сошлось — null, и никаких подробностей: чем именно не сошлось,
 * спрашивающему знать незачем.
 *
 * Как считается подпись (по описанию Telegram): из всех полей, кроме hash,
 * складываются строки «ключ=значение», сортируются по алфавиту и склеиваются
 * переводами строк. Эту строку подписывают ключом, который сам получен
 * подписью токена бота словом WebAppData.
 */
function ктоПрислал(initData) {
  if (!умеемГотовитьПриглашения()) return null;
  return ктоПодписал(initData, токенСейчас);
}

/**
 * То же самое, но токен передаётся доводом. Разделение не украшение:
 * проверку подписи надо уметь проверять, а сделать это, не зная токена,
 * иначе невозможно. Здесь его подставляет проверка — выдуманный, — а в
 * работе его подставляет ктоПрислал, и настоящий токен из файла остаётся
 * там, где ему и место.
 */
function ктоПодписал(initData, токен) {
  if (typeof токен !== 'string' || !токен) return null;
  if (typeof initData !== 'string' || !initData || initData.length > 4096) return null;

  let поля;
  try {
    поля = new URLSearchParams(initData);
  } catch (сбой) {
    return null;
  }
  const подпись = поля.get('hash');
  if (!подпись) return null;

  const строки = [];
  for (const пара of поля) {
    if (пара[0] === 'hash') continue;
    строки.push(пара[0] + '=' + пара[1]);
  }
  строки.sort();

  const ключ = crypto.createHmac('sha256', 'WebAppData').update(токен).digest();
  const наша = crypto.createHmac('sha256', ключ).update(строки.join('\n')).digest('hex');

  /* Сравниваем за одинаковое время: обычное сравнение строк заканчивается
     на первом различии, и по времени ответа подпись можно было бы
     подбирать по одному знаку. */
  const своё = Buffer.from(наша, 'utf8');
  const чужое = Buffer.from(String(подпись), 'utf8');
  if (своё.length !== чужое.length || !crypto.timingSafeEqual(своё, чужое)) return null;

  const когда = Number(поля.get('auth_date')) * 1000;
  if (!Number.isFinite(когда) || Date.now() - когда > ПОДПИСЬ_ГОДНА) return null;

  try {
    const кто = JSON.parse(поля.get('user') || 'null');
    const номер = кто && Number(кто.id);
    return Number.isInteger(номер) && номер > 0 ? номер : null;
  } catch (сбой) {
    return null;
  }
}

/**
 * Один запрос в Telegram. Ответ — разобранный JSON или null.
 * Все беды молчаливы нарочно: в тексте сетевой ошибки может оказаться
 * адрес запроса, а в адресе — токен.
 */
function спроситьTelegram(метод, тело) {
  /* Поддельная труба проверки. В работе её нет, и тогда запрос уходит
     в настоящий Telegram, как уходил всегда. */
  if (трубаСейчас) return Promise.resolve(трубаСейчас(метод, тело));
  return запросВTelegram(метод, тело);
}

/** Настоящий запрос в Telegram — тот самый, что был здесь всегда. */
function запросВTelegram(метод, тело) {
  return new Promise(function (готово) {
    let ответили = false;
    function закончить(что) {
      if (ответили) return;
      ответили = true;
      готово(что);
    }

    const данные = Buffer.from(JSON.stringify(тело), 'utf8');
    const запрос = https.request({
      hostname: 'api.telegram.org',
      path: '/bot' + ТОКЕН_БОТА + '/' + метод,
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Content-Length': данные.length }
    }, function (ответ) {
      let куски = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (кусок) { куски += кусок; });
      ответ.on('end', function () {
        try {
          закончить(JSON.parse(куски));
        } catch (сбой) {
          закончить(null);
        }
      });
    });
    запрос.on('error', function () { закончить(null); });
    запрос.setTimeout(ЖДЁМ_TELEGRAM, function () {
      запрос.destroy();
      закончить(null);
    });
    запрос.write(данные);
    запрос.end();
  });
}

/* Наша ссылка-приглашение и ничего кроме: рассылать через бота чужие
   адреса нельзя, иначе сервер станет чужим почтальоном. */
const НАША_ССЫЛКА =
  /^https:\/\/t\.me\/[A-Za-z0-9_]{3,64}\/[A-Za-z0-9_]{1,64}\?startapp=[A-Za-z0-9_-]{1,512}$/;

function этоНашаСсылка(ссылка) {
  return typeof ссылка === 'string' && ссылка.length <= 300 && НАША_ССЫЛКА.test(ссылка);
}

/* Ссылка на само приложение, без кода комнаты, — для «Похвастаться победой».
   Тот же t.me, тот же бот; хвост — только метка игры (startapp=shashki),
   и ничего больше: друг откроет игру и сыграет сам. Метки — те же слова,
   что разбирает js/сеть.js; дурак ходит без метки, как и все старые ссылки. */
const МЕТКИ_ИГР = { 'дурак': '', 'шашки': 'shashki' };
const НАША_ССЫЛКА_НА_ИГРУ =
  /^https:\/\/t\.me\/[A-Za-z0-9_]{3,64}\/[A-Za-z0-9_]{1,64}(?:\?startapp=(shashki|durak))?$/;

function этоНашаСсылкаНаИгру(ссылка) {
  return typeof ссылка === 'string' && ссылка.length <= 200 && НАША_ССЫЛКА_НА_ИГРУ.test(ссылка);
}

/** Какую игру откроет ссылка: 'дурак', 'шашки' или '' — если ссылка не наша. */
function играПоСсылке(ссылка) {
  const разбор = этоНашаСсылкаНаИгру(ссылка) ? ссылка.match(НАША_ССЫЛКА_НА_ИГРУ) : null;
  if (!разбор) return '';
  const метка = разбор[1] || '';
  for (const игра of Object.keys(МЕТКИ_ИГР)) {
    if (МЕТКИ_ИГР[игра] === метка) return игра;
  }
  return метка === 'durak' ? 'дурак' : '';
}

/* ---------------------------------------------------------------------
   Слова о победе для чата. Правило одно на игру, и записано оно у самой
   игры: у дурака — «словаПобедыДляЧата» в js/game.js, у шашек — то же имя
   в js/шашки-похвастаться.js. Здесь оба повторены буква в букву, потому
   что бот рассылает только текст, собранный сервером (чужой текст
   не рассылаем), а запасной путь в браузере пишет те же слова сам.
   Разойдутся — человек увидит в чате не то, что было на кнопке.
   Без «я выиграл» нарочно: без рода и без хвастовства за человека.
   --------------------------------------------------------------------- */
const СТОЛ_СЛОВАМИ = { 3: 'втроём', 4: 'вчетвером', 5: 'впятером', 6: 'вшестером' };
const УРОВЕНЬ_В_ТВОРИТЕЛЬНОМ = { 'лёгкий': 'лёгким', 'обычный': 'обычным', 'сложный': 'сложным' };

/* Серия побед подряд — от какой длины о ней стоит сказать. Одна победа —
   не серия; со второй уже есть чем хвастаться. Только у шашек: у дурака
   слова на кнопке серию не называют, и серверу называть её нельзя. */
const СЕРИЯ_СТОИТ_СЛОВ = 2;
const САМАЯ_ДЛИННАЯ_СЕРИЯ = 10000;

/**
 * Разобрать описание победы, присланное игрой. Годное — вернуть чистым,
 * поле за полем; негодное — null. Клиенту не верим: каждое поле сверяется
 * со списком допустимого, свободного текста здесь нет вовсе.
 */
function описаниеПобеды(тело) {
  if (!тело || typeof тело !== 'object') return null;
  if (!Object.prototype.hasOwnProperty.call(МЕТКИ_ИГР, тело.игра)) return null;
  if (тело.исход !== 'победа') return null;
  if (тело.соперники !== 'боты' && тело.соперники !== 'люди') return null;
  const игроков = Number(тело.игроков);
  if (!Number.isInteger(игроков) || игроков < 2 || игроков > 6) return null;
  const уровень = typeof тело.уровень === 'string' && УРОВЕНЬ_В_ТВОРИТЕЛЬНОМ[тело.уровень] ? тело.уровень : '';
  const серия = Number(тело.серия);
  return {
    игра: тело.игра,
    соперники: тело.соперники,
    уровень: уровень,
    игроков: игроков,
    парами: тело.парами === true,
    серия: Number.isInteger(серия) && серия > 0 && серия <= САМАЯ_ДЛИННАЯ_СЕРИЯ ? серия : 0
  };
}

/** Те же слова, что у игр: «словаПобедыДляЧата» в js/game.js и в js/шашки-похвастаться.js. */
function словаПобеды(описание) {
  const бот = (УРОВЕНЬ_В_ТВОРИТЕЛЬНОМ[описание.уровень] || 'обычным') + ' ботом';
  if (описание.игра === 'шашки') {
    const серия = описание.серия >= СЕРИЯ_СТОИТ_СЛОВ ? ' — уже ' + описание.серия + ' подряд' : '';
    return 'Победа в шашках над ' + бот + серия + '. Сыграем?';
  }
  const стол = описание.парами ? 'парами' : (СТОЛ_СЛОВАМИ[описание.игроков] || '');
  if (описание.соперники === 'люди') {
    return 'Победа в подкидном дураке ' + (стол ? стол + ' с друзьями' : 'с другом') + '. Сыграем?';
  }
  return 'Победа в подкидном дураке над ' + бот + (стол ? ' ' + стол : '') + '. Сыграем?';
}

/* Кто когда просил подготовить приглашение. Нужно, чтобы один игрок не мог
   дёргать Telegram без остановки: подпись у него настоящая, значит шлагбаум
   на подделки тут не поможет, а звать чужую службу без нужды нельзя.
   Три секунды — это дольше, чем человек выбирает чат, и короче, чем ему
   ждать второй попытки. */
const ПАУЗА_МЕЖДУ_ПРИГЛАШЕНИЯМИ = 3000;
const ПОМНИМ_ПРОСИВШИХ = 500;
const когдаПросили = new Map();

/** Не частит ли этот игрок. Заодно прибираем старые записи. */
function проситьМожно(кто) {
  const сейчас = Date.now();
  if (когдаПросили.size > ПОМНИМ_ПРОСИВШИХ) {
    for (const [номер, когда] of когдаПросили) {
      if (сейчас - когда > ПАУЗА_МЕЖДУ_ПРИГЛАШЕНИЯМИ) когдаПросили.delete(номер);
    }
  }
  const прошлый = когдаПросили.get(кто) || 0;
  if (сейчас - прошлый < ПАУЗА_МЕЖДУ_ПРИГЛАШЕНИЯМИ) return false;
  когдаПросили.set(кто, сейчас);
  return true;
}

/** Сообщение «за стол»: ссылка с кодом комнаты, текст — прежний. */
function сообщениеЗаСтол(тело) {
  const ссылка = тело && тело.ссылка;
  if (!этоНашаСсылка(ссылка)) return null;
  return {
    вид: 'стол',
    заголовок: 'Позвать за стол',
    пояснение: 'Друг откроет игру и сразу сядет за ваш стол',
    текст: 'Играем в подкидного дурака? Стол уже собран — заходите: ' + ссылка,
    кнопка: 'Сесть за стол',
    ссылка: ссылка
  };
}

/** Сообщение о победе: ссылка на само приложение, слова собирает сервер. */
function сообщениеОПобеде(тело) {
  const ссылка = тело && тело.ссылка;
  if (!этоНашаСсылкаНаИгру(ссылка)) return null;
  const описание = описаниеПобеды(тело);
  if (!описание) return null;
  /* Ссылка обязана вести в ту игру, о которой слова: под «Победа в шашках»
     кнопка «Сыграть» не имеет права открыть карты. Расхождение — отказ. */
  if (играПоСсылке(ссылка) !== описание.игра) return null;
  return {
    вид: 'победа',
    заголовок: 'Похвастаться победой',
    пояснение: 'Друг откроет игру и сыграет сам',
    текст: словаПобеды(описание) + ' ' + ссылка,
    кнопка: 'Сыграть',
    ссылка: ссылка
  };
}

/**
 * Дверь /приглашение. Игра присылает свою initData и готовую ссылку,
 * получает номер подготовленного сообщения — и показывает выбор чата
 * сама, средствами Telegram. С полем вид: 'победа' и описанием победы
 * (игра, исход, соперники, уровень, игроков, парами) готовится не зов
 * за стол, а «похвастаться»: ссылка без кода, кнопка «Сыграть».
 *
 * Ответ нарочно небогатый: «умеем» и «ок». Никаких объяснений, почему
 * не вышло: игре они не нужны (у неё один запасной путь на все случаи),
 * а нам за каждым таким объяснением пришлось бы следить, чтобы в него
 * не просочился токен.
 */
async function приглашение(тело, ответ) {
  if (!умеемГотовитьПриглашения()) {
    return ответить(ответ, 200, { умеем: false });
  }
  const кто = ктоПрислал(тело && тело.initData);
  if (!кто) return ответить(ответ, 200, { умеем: true, ок: false });

  /* Два вида сообщений одной дверью: зов за стол (ссылка с кодом) и
     похвастаться победой (ссылка на само приложение, без кода). Что писать,
     решает сервер по полям, а не по присланному тексту — бот чужой текст
     не рассылает, это правило стоит нарочно. */
  const сообщение = тело && тело.вид === 'победа'
    ? сообщениеОПобеде(тело)
    : сообщениеЗаСтол(тело);
  if (!сообщение || !проситьМожно(кто)) {
    return ответить(ответ, 200, { умеем: true, ок: false });
  }

  const итог = await спроситьTelegram('savePreparedInlineMessage', {
    user_id: кто,
    allow_user_chats: true,
    allow_group_chats: true,
    result: {
      type: 'article',
      id: сообщение.вид + '-' + Date.now().toString(36),
      title: сообщение.заголовок,
      description: сообщение.пояснение,
      input_message_content: {
        message_text: сообщение.текст,
        link_preview_options: { is_disabled: true }
      },
      reply_markup: {
        inline_keyboard: [[{ text: сообщение.кнопка, url: сообщение.ссылка }]]
      }
    }
  });

  if (!итог || итог.ok !== true || !итог.result || !итог.result.id) {
    return ответить(ответ, 200, { умеем: true, ок: false });
  }
  return ответить(ответ, 200, { умеем: true, ок: true, номерСообщения: String(итог.result.id) });
}

/* ---------------------------------------------------------------------
   Знакомые: с кем человек уже играл и кто из них сейчас за столом

   Зачем. Позвать друга можно только двумя способами: продиктовать код
   из четырёх знаков или отправить ссылку. Оба требуют, чтобы человек
   заранее знал, кому писать. Список знакомых отвечает на вопрос проще:
   вот те, с кем вы уже сидели за одним столом, и вот кто из них
   прямо сейчас в игре.

   Списка друзей Telegram приложению не даёт, и это правильно. Поэтому
   источник у списка ровно один — наша собственная память о том, кто с кем
   играл (server/знакомые.js). Она заводится сама в миг раздачи карт.

   Два правила, которые здесь важнее удобства:

     1) Кто спрашивает — решает подпись Telegram, а не тело запроса.
        Иначе любой прислал бы чужой номер и посмотрел бы чужой список.

     2) Номера Telegram наружу не уходят ВОВСЕ. Номера нужны только внутри:
        по ним мы спрашиваем комнаты, кто сейчас за столом. Ответ игроку
        собирается вручную, поле за полем, и в нём есть только имя и
        признак «сейчас играет».
   --------------------------------------------------------------------- */

/**
 * Дверь POST /знакомые. Тело — { initData }, и больше ничего.
 * Ответ — { узналиВас, знакомые: [ { имя, сейчасИграет } ] },
 * в порядке «с кем играли позже, тот выше».
 *
 * Подпись не сошлась (игру открыли не в Telegram, подпись просрочена,
 * у сервера нет токена бота) — отвечаем спокойно: список пустой и
 * «вас не узнали». Это не ошибка, а обычное дело: в браузере на
 * компьютере игра работает и так, просто знакомств у неё нет.
 */
function списокЗнакомых(тело, ответ) {
  const кто = ктоПрислал(тело && тело.initData);
  if (!кто) return ответить(ответ, 200, { узналиВас: false, знакомые: [] });

  const мои = знакомые.знакомыеИгрока(кто);
  const номера = мои.map(function (друг) { return друг.номер; });
  const заСтолом = комнаты.ктоСейчасЗаСтолом(номера);

  /* Собираем ответ поле за полем. Разложить сюда готовую запись целиком
     (спред, Object.assign) нельзя: в записи лежит номер Telegram, и он
     утёк бы наружу молча, а такую утечку потом ищут неделями. */
  const список = [];
  for (const друг of мои) {
    список.push({
      имя: друг.имя || '',
      /* Чем игра назовёт этого знакомого, когда попросит его позвать.
         Номер Telegram наружу по-прежнему не выходит: вместо него едет
         слово, которое ничего не значит нигде, кроме этого сервера
         (см. ключДруга). */
      ключ: ключДруга(кто, друг.номер),
      сейчасИграет: заСтолом.has(друг.номер),
      /* Во что играли в последний раз — одно слово из закрытого набора
         («дурак», «шашки») или пусто у старых знакомств. Игр стало две,
         и без этого слова список знакомых молчит о главном: звать ли
         этого человека за карты или за доску. */
      игра: друг.игра || ''
    });
  }
  return ответить(ответ, 200, { узналиВас: true, знакомые: список });
}

/* ---------------------------------------------------------------------
   ПОЗВАТЬ ЗНАКОМОГО ОДНИМ НАЖАТИЕМ: бот сам пишет ему в Telegram

   Зачем. Позвать друга за стол можно было только через себя: скопируй
   ссылку, найди чат, отправь. Владелец сказал прямо: «Выбрал его — всё,
   оно отправляется». Позвать по-настоящему мы вправе: всякий, кто есть
   в списке знакомых, уже играл с нами и уже открывал нашего бота —
   значит бот может написать ему сам, письмом с кнопкой «Войти».

   Три правила, которые здесь важнее удобства.

     1) Звать можно ТОЛЬКО тех, с кем человек правда играл. Иначе бот
        через неделю станет рассылкой, и запретят его нам всем разом.
        Проверяется не словом в запросе, а устройством: игра называет
        знакомого «ключом» из ответа /знакомые, а ключ — подпись пары
        «я и он» секретом этого сервера. Чужой ключ ни к чему не подойдёт,
        свой — только к своей паре.

     2) У приглашаемого есть «не звать меня». Кнопка стоит в самом письме,
        нажатие приходит боту, бот говорит серверу (дверь /не-звать),
        и отказ переживает перезапуск (server/не-звать.js).

     3) Номера Telegram наружу по-прежнему не выходят. Игра номера не
        видит и прислать его не может: у неё есть только ключ.

   Что здесь НЕ проверяется, и это сказано нарочно: жив ли стол, за
   который зовут. Стол создаёт та же игра мгновением раньше, а разбирать
   код комнаты из ссылки значило бы завести здесь вторую копию разбора
   startapp из js/сеть.js — и однажды эти двое разошлись бы.
   --------------------------------------------------------------------- */

/* Чем подписываются ключи знакомых. Секрет новый при каждом запуске —
   и это не лень, а решение: ключ живёт минуты (открыл экран — позвал),
   хранить его дольше незачем, а уехавший ключ после перезапуска просто
   не подойдёт, и игра честно скажет «список устарел, откройте заново». */
const СЕКРЕТ_КЛЮЧЕЙ = crypto.randomBytes(32);

/* Половины sha256 хватает с запасом: подобрать ключ нельзя, а в ответе
   он стоит у каждого знакомого — незачем гонять лишние знаки. */
const ДЛИНА_КЛЮЧА = 32;

/**
 * Ключ знакомого — слово, которым игра назовёт человека, не зная его
 * номера. Считается из пары «кто спрашивает» и «о ком речь», поэтому
 * один и тот же друг у разных игроков зовётся по-разному, и подсмотренный
 * у соседа ключ не работает.
 */
function ключДруга(мойНомер, номерДруга) {
  return crypto.createHmac('sha256', СЕКРЕТ_КЛЮЧЕЙ)
    .update(мойНомер + ':' + номерДруга, 'utf8')
    .digest('hex').slice(0, ДЛИНА_КЛЮЧА);
}

/**
 * Найти знакомого по ключу: { номер, имя } или null.
 * Ключи пересчитываем по СВЕЖЕМУ списку знакомых спрашивающего — значит,
 * подойти может только тот, с кем он и правда играл. Список короткий
 * (не больше 50), перебор здесь ничего не стоит.
 */
function найтиДругаПоКлючу(кто, ключ) {
  if (typeof ключ !== 'string' || ключ.length !== ДЛИНА_КЛЮЧА) return null;
  for (const друг of знакомые.знакомыеИгрока(кто)) {
    if (ключДруга(кто, друг.номер) === ключ) return друг;
  }
  return null;
}

/* ---------- Как часто можно звать ----------

   Три разных предела, и каждый закрывает свою беду:
     минута между зовами — от нечаянного двойного нажатия;
     пять зовов в час — чтобы одним человеком нельзя было разослать
     письма всему своему списку знакомых подряд;
     одному и тому же — раз в час, чтобы настойчивый друг не превратил
     кнопку в стук в дверь.
   Считаем попытки, а не удачи: Telegram дёргать без нужды нельзя и тогда,
   когда письмо не уходит. */
const ЗОВ_НЕ_ЧАЩЕ = 60 * 1000;
const ЗОВОВ_В_ЧАС = 5;
const ЧАС = 60 * 60 * 1000;
const ПОМНИМ_ЗОВУЩИХ = 500;

const зовыИгрока = new Map();        // номер зовущего → времена зовов за час
const комуЗвали = new Map();         // «зовущий:знакомый» → когда звали

/** Прибраться в памяти зовов — чтобы она не росла на людном сервере. */
function прибратьЗовы(сейчас) {
  if (зовыИгрока.size > ПОМНИМ_ЗОВУЩИХ) {
    for (const [номер, времена] of зовыИгрока) {
      const свежие = времена.filter(function (когда) { return сейчас - когда < ЧАС; });
      if (свежие.length) зовыИгрока.set(номер, свежие);
      else зовыИгрока.delete(номер);
    }
  }
  if (комуЗвали.size > ПОМНИМ_ЗОВУЩИХ) {
    for (const [пара, когда] of комуЗвали) {
      if (сейчас - когда >= ЧАС) комуЗвали.delete(пара);
    }
  }
}

/** Рано ли звать: словами для человека или пусто, если можно. */
function почемуЗватьРано(кто, кого) {
  const сейчас = Date.now();
  прибратьЗовы(сейчас);

  const мои = (зовыИгрока.get(кто) || []).filter(function (когда) {
    return сейчас - когда < ЧАС;
  });
  const последний = мои.length ? мои[мои.length - 1] : 0;
  if (последний && сейчас - последний < ЗОВ_НЕ_ЧАЩЕ) {
    return 'Вы только что кого-то позвали. Следующего можно позвать через минуту.';
  }
  if (мои.length >= ЗОВОВ_В_ЧАС) {
    return 'За час можно позвать ' + ЗОВОВ_В_ЧАС + ' человек. Попробуйте позже — ' +
           'или отправьте ссылку сами.';
  }
  const когдаЕму = комуЗвали.get(кто + ':' + кого) || 0;
  if (когдаЕму && сейчас - когдаЕму < ЧАС) {
    return 'Этого знакомого вы уже звали — письмо ему пришло. Повторить можно через час.';
  }
  return '';
}

/** Запомнить попытку зова. Зовём до Telegram: беречь надо и чужую службу. */
function записатьЗов(кто, кого) {
  const сейчас = Date.now();
  const мои = (зовыИгрока.get(кто) || []).filter(function (когда) {
    return сейчас - когда < ЧАС;
  });
  мои.push(сейчас);
  зовыИгрока.set(кто, мои);
  комуЗвали.set(кто + ':' + кого, сейчас);
}

/* ---------- Ссылка, имя и само письмо ---------- */

/* Та же ссылка, что собирает игра (ссылкаНаМиниПриложение в js/сеть.js):
   t.me/БОТ/ПРИЛОЖЕНИЕ?startapp=[метка игры_]КОД-адрес буквами.
   Из неё берём три вещи: имя бота (оно обязано быть нашим), метку игры —
   чтобы письмо называло ту игру, которую откроет кнопка, — и хвост со
   своим кодом стола: его сверяем с тем кодом, что прислан отдельным
   полем (см. позватьЗнакомого), чтобы кнопка в письме вела туда же,
   откуда позвали, а не в чужую комнату. */
const ССЫЛКА_ЗА_СТОЛ =
  /^https:\/\/t\.me\/([A-Za-z0-9_]{3,64})\/[A-Za-z0-9_]{1,64}\?startapp=(?:(shashki|durak)_)?([A-Za-z0-9_-]{1,512})$/;

/* Метка в ссылке → игра словами. Набор закрытый: это те же метки, что
   в МЕТКИ_ИГР у js/сеть.js. Метки нет вовсе — дурак, как было всегда. */
const ИГРА_ПО_МЕТКЕ = { shashki: 'шашки', durak: 'дурак' };

/**
 * Разобрать ссылку за стол: { имяБота, игра, код, хвост } или null, если она
 * не наша. хвост — адрес сервера буквами (то, что после первого дефиса),
 * или '' — если адреса в ссылке нет.
 */
function разобратьСсылкуЗаСтол(ссылка) {
  if (!этоНашаСсылка(ссылка)) return null;
  const разбор = String(ссылка).match(ССЫЛКА_ЗА_СТОЛ);
  if (!разбор) return null;
  // Хвост — «код» или «код-буквы_адреса»: код стола всегда до первого дефиса.
  const всё = разбор[3] || '';
  const граница = всё.indexOf('-');
  const код = граница === -1 ? всё : всё.slice(0, граница);
  const хвост = граница === -1 ? '' : всё.slice(граница + 1);
  return { имяБота: разбор[1], игра: ИГРА_ПО_МЕТКЕ[разбор[2]] || 'дурак', код: код, хвост: хвост };
}

/* Как зовут нашего бота в Telegram. Спрашиваем у самого Telegram один
   раз за запуск: в настройках сервера имени бота нет, а письмо с кнопкой
   в ЧУЖОГО бота слать нельзя — так наш бот стал бы почтальоном для кого
   угодно. Не ответил — письма не будет, и это правильнее, чем отправить
   человеку ссылку неизвестно куда. */
let имяБотаВTelegram = '';

async function имяНашегоБота() {
  if (имяБотаВTelegram) return имяБотаВTelegram;
  const итог = await спроситьTelegram('getMe', {});
  const имя = итог && итог.ok === true && итог.result && итог.result.username;
  if (typeof имя === 'string' && имя) имяБотаВTelegram = имя;
  return имяБотаВTelegram;
}

/* Сколько знаков имени показываем в письме. Столько же помнит о человеке
   память знакомств (привестиИмя в server/знакомые.js). */
const ИМЯ_В_ПИСЬМЕ = 32;

/**
 * Имя зовущего для письма. Берём из подписи — то есть у самого Telegram,
 * а не из тела запроса. Переводы строк и прочие управляющие знаки
 * вычищаем: имя стоит первым словом письма, и подделывать им вид письма
 * нельзя.
 */
function имяДляПисьма(initData) {
  const сырое = имяИзПодписи(initData);
  const чистое = String(сырое || '').replace(/[\s\x00-\x1f]+/g, ' ').trim();
  return чистое.slice(0, ИМЯ_В_ПИСЬМЕ);
}

/* Как называется игра в письме. Слова закрытым набором: подставлять
   сюда что-то пришедшее снаружи нельзя. */
const ИГРА_В_ПИСЬМЕ = { 'дурак': 'в подкидного дурака', 'шашки': 'в шашки' };

/* Что бот кладёт в кнопку отказа. Это слово он же получит обратно,
   когда человек нажмёт (см. bot/бот.js). */
const ОТКАЗ_ОТ_ЗОВОВ = 'не-звать';

/**
 * Письмо знакомому: короткий текст и две кнопки — «Войти» за стол и
 * «Не звать меня». Собирается здесь целиком, поле за полем: чужого
 * текста бот не рассылает, это давнее правило и оно не слабеет.
 */
function письмоЗнакомому(имяЗовущего, игра, ссылка) {
  const кто = имяЗовущего || 'Знакомый по игре';
  const воЧто = ИГРА_В_ПИСЬМЕ[игра] || ИГРА_В_ПИСЬМЕ['дурак'];
  return {
    текст: кто + ' зовёт вас сыграть ' + воЧто + '.\n' +
           'Нажмите «Войти» — и вы сразу за столом.',
    кнопки: {
      inline_keyboard: [
        [{ text: 'Войти', url: ссылка }],
        [{ text: 'Не звать меня', callback_data: ОТКАЗ_ОТ_ЗОВОВ }]
      ]
    }
  };
}

/* Слова отказов. Все до одного написаны для человека и показываются
   ему как есть (правило сервера: тексты отказов — словами игрока).
   Про Telegram и его беды здесь нет ни слова: в них может оказаться
   что угодно, вплоть до адреса запроса с токеном. */
const ЗОВ_НЕ_УМЕЕМ = 'Сервер игры не умеет отправлять письма — позовите друга ссылкой.';
const ЗОВ_НЕ_В_TELEGRAM = 'Позвать письмом можно только из Telegram.';
const ЗОВ_СПИСОК_УСТАРЕЛ = 'Список знакомых устарел — откройте экран заново и попробуйте ещё раз.';
const ЗОВ_СТОЛ_НЕ_ТОТ = 'Стол не найден — создайте стол заново и позовите ещё раз.';
const ЗОВ_БОТ_НЕ_ПИШЕТ = 'Друг ещё не открывал нашего бота — отправьте ему ссылку сами.';
const ЗОВ_САМ_ПРОСИЛ = 'Этот знакомый просил не звать его письмами. Отправьте ссылку сами, ' +
                       'если ждёте именно его.';
const ЗОВ_НЕ_ВЫШЛО = 'Письмо отправить не вышло. Попробуйте через минуту или отправьте ссылку сами.';
const ЗОВ_УЖЕ_ЗА_СТОЛОМ = 'Он уже за столом.';

/** Короткий отказ одной строкой: «можноПоСтаринке» — стоит ли предлагать ссылку. */
function зовНеВышел(ответ, причина, поСтаринке) {
  return ответить(ответ, 200, {
    ок: false,
    причина: причина,
    можноПоСтаринке: поСтаринке === true
  });
}

/**
 * Дверь POST /позвать. Тело — { initData, ключ, ссылка }.
 * Ответ — { ок, кого, причина, можноПоСтаринке }: имя того, кого позвали,
 * или человеческое объяснение, почему письма не будет.
 *
 * Шлагбаума здесь нет нарочно, как и у соседней двери /приглашение:
 * без верной подписи Telegram эта дверь не делает ничего вовсе,
 * а от частых зовов защищают свои пределы (почемуЗватьРано).
 */
async function позватьЗнакомого(тело, ответ) {
  const целое = тело && typeof тело === 'object' ? тело : {};
  if (!умеемГотовитьПриглашения()) return зовНеВышел(ответ, ЗОВ_НЕ_УМЕЕМ, true);

  const кто = ктоПрислал(целое.initData);
  if (!кто) return зовНеВышел(ответ, ЗОВ_НЕ_В_TELEGRAM, true);

  const куда = разобратьСсылкуЗаСтол(целое.ссылка);
  if (!куда) return зовНеВышел(ответ, ЗОВ_СТОЛ_НЕ_ТОТ, false);

  /* Стол проверяем трижды, и ни один довод не лишний:
       — код в самой ссылке обязан совпасть с тем, что прислан отдельным
         полем «код» — иначе кнопка в письме вела бы не туда, откуда звали;
       — стол с этим кодом обязан быть жив прямо сейчас — иначе письмо
         зовёт в комнату, которой уже нет;
       — зовущий обязан сам сейчас сидеть за ЭТИМ столом (узнаём его по
         подписи Telegram) — иначе через эту дверь можно было бы затащить
         знакомого в чужую комнату, где зовущего вовсе нет. И только после
         этого код годится для вопроса «друг уже здесь?»: спроси мы раньше,
         перебором кодов можно было бы узнать, за каким столом сидит друг.
     Без этой проверки дверь принимала любой код в ссылке на веру. */
  const код = typeof целое.код === 'string' ? целое.код : '';
  if (!код || код.toUpperCase() !== куда.код.toUpperCase()) {
    return зовНеВышел(ответ, ЗОВ_СТОЛ_НЕ_ТОТ, false);
  }
  if (!комнаты.состояниеСтола(код).есть) {
    return зовНеВышел(ответ, ЗОВ_СТОЛ_НЕ_ТОТ, false);
  }
  if (!комнаты.сидитЗаСтолом(код, кто)) {
    return зовНеВышел(ответ, ЗОВ_СТОЛ_НЕ_ТОТ, false);
  }

  const друг = найтиДругаПоКлючу(кто, целое.ключ);
  if (!друг) return зовНеВышел(ответ, ЗОВ_СПИСОК_УСТАРЕЛ, true);
  // Позвать самого себя нельзя даже случайно: знакомство с собой не заводится,
  // но проверка стоит копейку, а письмо самому себе выглядело бы поломкой.
  if (друг.номер === кто) return зовНеВышел(ответ, ЗОВ_СПИСОК_УСТАРЕЛ, false);
  /* Друг уже сидит за этим самым столом, где сидит и зовущий (проверено
     выше), — письмо «зовёт вас» было бы бессмыслицей. Про другие столы
     этот ответ не говорит ничего. Проверяем до пределов: такой зов их
     не тратит. */
  if (комнаты.сидитЗаСтолом(код, друг.номер)) return зовНеВышел(ответ, ЗОВ_УЖЕ_ЗА_СТОЛОМ, false);

  const запрет = неЗвать.почемуНеЗвать(друг.номер);
  if (запрет === неЗвать.ПРИЧИНЫ.сам) return зовНеВышел(ответ, ЗОВ_САМ_ПРОСИЛ, true);
  if (запрет) return зовНеВышел(ответ, ЗОВ_БОТ_НЕ_ПИШЕТ, true);

  const рано = почемуЗватьРано(кто, друг.номер);
  if (рано) return зовНеВышел(ответ, рано, false);

  /* Кнопка в письме обязана вести к НАШЕМУ боту. Иначе через эту дверь
     можно было бы разослать знакомым ссылку на чужое приложение —
     от имени бота, которому они доверяют. */
  const наш = await имяНашегоБота();
  if (!наш) return зовНеВышел(ответ, ЗОВ_НЕ_ВЫШЛО, true);
  if (наш.toLowerCase() !== куда.имяБота.toLowerCase()) {
    return зовНеВышел(ответ, ЗОВ_СТОЛ_НЕ_ТОТ, false);
  }

  записатьЗов(кто, друг.номер);

  const письмо = письмоЗнакомому(имяДляПисьма(целое.initData), куда.игра, целое.ссылка);
  const итог = await спроситьTelegram('sendMessage', {
    chat_id: друг.номер,
    text: письмо.текст,
    link_preview_options: { is_disabled: true },
    reply_markup: письмо.кнопки
  });

  if (итог && итог.ok === true) {
    return ответить(ответ, 200, { ок: true, кого: друг.имя || '', причина: '', можноПоСтаринке: false });
  }

  /* 403 — «бот не может писать этому человеку»: тот не открывал бота или
     закрыл ему рот. Помним сутки, чтобы не долбиться в закрытую дверь на
     каждое нажатие. Наружу идёт только номер кода — в словах Telegram
     может оказаться что угодно, и пересказывать их мы не будем. */
  if (итог && Number(итог.error_code) === 403) {
    неЗвать.запретить(друг.номер, неЗвать.ПРИЧИНЫ.ботНеПишет);
    return зовНеВышел(ответ, ЗОВ_БОТ_НЕ_ПИШЕТ, true);
  }
  return зовНеВышел(ответ, ЗОВ_НЕ_ВЫШЛО, true);
}

/**
 * Дверь POST /не-звать. Тело — { пропускБота, кого }.
 * Только для нашего бота: человек нажал в письме «Не звать меня», а
 * нажатия приходят боту, не серверу. Пропуск — тот же, что у стола из
 * чата: обе стороны считают его из токена сами, по сети токен не ходит.
 */
function большеНеЗвать(тело, ответ) {
  const целое = тело && typeof тело === 'object' ? тело : {};
  if (!этоПропускБота(целое.пропускБота)) {
    return ответить(ответ, 403, { ок: false, ошибка: 'Эта дверь только для бота игры' });
  }
  const кого = Number(целое.кого);
  if (!Number.isInteger(кого) || кого <= 0) {
    return ответить(ответ, 400, { ок: false, ошибка: 'Не сказано, кого не звать' });
  }
  неЗвать.запретить(кого, неЗвать.ПРИЧИНЫ.сам);
  return ответить(ответ, 200, { ок: true });
}

/* ---------------------------------------------------------------------
   ЛЕНТА БОТА: письма о событиях стола (server/лента.js)

   Кто-то сел за стол, стол собрался, хозяин начал, кто-то зовёт сыграть
   ещё — а человек свернул игру. Комнаты объявляют такие события, лента
   решает, кому писать, а здесь только провода к настоящему миру: письмо
   идёт через ту же трубу к Telegram, что и зов знакомого, отказы — из той
   же памяти «не звать». Нет токена бота — лента молчит, всё как раньше.
   --------------------------------------------------------------------- */

/* Имя бота для проверки ссылки — без ожидания. Опрос «что нового» идёт
   у каждого игрока постоянно, и ждать в нём getMe (до пяти секунд) нельзя.
   Имя неизвестно — ссылку в этот раз отбрасываем (страница пришлёт её
   снова со следующим опросом), а getMe запускаем в фоне: не больше одного
   запроса разом и не чаще раза в минуту, если Telegram не отвечает. */
const ПАУЗА_МЕЖДУ_GETME = 60 * 1000;
let getMeИдёт = false;
let последнийGetMe = 0;

function имяБотаБезОжидания() {
  if (имяБотаВTelegram) return имяБотаВTelegram;
  if (getMeИдёт || Date.now() - последнийGetMe < ПАУЗА_МЕЖДУ_GETME) return '';
  getMeИдёт = true;
  последнийGetMe = Date.now();
  // Ответ запомнит сама имяНашегоБота; сбой молчалив, как и все беды Telegram.
  имяНашегоБота().catch(function () { return ''; }).then(function () {
    getMeИдёт = false;
  });
  return '';
}

/* Адрес «хоста» из заголовка: имя и, может быть, порт. Всё прочее
   (пробелы, «@», «/») — не адрес, а попытка подсунуть что-то при разборе. */
const ИМЯ_ХОСТА = /^(?:[a-z0-9.-]+|\[[0-9a-f:.]+\])(?::\d{1,5})?$/;

/* Свой компьютер по имени из заголовка Host — как СВОЙ_КОМПЬЮТЕР, но без схемы. */
const СВОЙ_ХОСТ = /^(localhost|127\.0\.0\.1)$/;

/**
 * Ведёт ли хвост ссылки (адрес сервера буквами base64url, как собирает
 * буквамиИзАдреса в js/сеть.js) на этот самый сервер. Сравниваем с тем
 * адресом, по которому пришёл запрос: за туннелем cloudflared заголовок
 * Host — это публичный адрес туннеля (подделать его нельзя: по нему туннель
 * и находит наш сервер). X-Forwarded-Host не смотрим нарочно: его туннель
 * пропускает от клиента как есть, и подставить туда можно что угодно.
 * Хвоста нет — ссылка без адреса, игра возьмёт свой: это годится.
 */
function хвостВедётСюда(хвост, запрос) {
  if (!хвост) return true;
  let адрес;
  try {
    адрес = new URL(Buffer.from(хвост, 'base64url').toString('utf8'));
  } catch (сбой) {
    return false;
  }
  if (адрес.protocol !== 'https:' && адрес.protocol !== 'http:') return false;
  const заголовок = String((запрос && запрос.headers && запрос.headers.host) || '').trim().toLowerCase();
  if (!ИМЯ_ХОСТА.test(заголовок)) return false;
  let сюда;
  try {
    сюда = new URL('http://' + заголовок);
  } catch (сбой) {
    return false;
  }
  if (сюда.hostname !== адрес.hostname) return false;
  /* Снаружи к серверу ходят только через туннель, а он всегда https.
     Обычный http годится лишь для своего компьютера — там туннеля нет. */
  if (адрес.protocol !== 'https:' && !СВОЙ_ХОСТ.test(сюда.hostname)) return false;
  /* Порт в заголовке пишут, только если он не обычный. Нет порта — и в ссылке
     его быть не должно: URL сам стирает обычный порт своей схемы (443 у https,
     80 у http), так что пустой порт ссылки — это ровно «пусто или обычный».
     Иначе ссылка с чужим портом того же имени прошла бы как «сюда». */
  if (!сюда.port) return адрес.port === '';
  return сюда.port === (адрес.port || (адрес.protocol === 'https:' ? '443' : '80'));
}

/**
 * Ссылка за стол для кнопки «Открыть стол» — или null. Годится только
 * наша ссылка (тот же разбор, что у /позвать): на нашего бота, на ЭТОТ
 * стол, на эту игру и на этот сервер. Иначе бот от своего имени повёл бы
 * сидящих за столом куда угодно. Негодное отбрасываем молча — письмо
 * просто уйдёт без кнопки. Ничего не ждёт.
 */
function ссылкаДляПисьма(ссылка, комната, запрос) {
  if (!умеемГотовитьПриглашения() || !комната) return null;
  const куда = разобратьСсылкуЗаСтол(ссылка);
  if (!куда || typeof комната.код !== 'string') return null;
  if (комната.код.toUpperCase() !== куда.код.toUpperCase()) return null;
  if (куда.игра !== комнаты.играСтола(комната)) return null;
  if (!хвостВедётСюда(куда.хвост, запрос)) return null;
  const наш = имяБотаБезОжидания();
  if (!наш || наш.toLowerCase() !== куда.имяБота.toLowerCase()) return null;
  return ссылка;
}

/** Ссылка от страницы в «что нового»: проверить и отдать комнате (та возьмёт только у хозяина). */
function принятьСсылкуЗаСтол(ссылка, я, запрос) {
  if (ссылка === undefined || ссылка === null || ссылка === '') return;
  const годная = ссылкаДляПисьма(ссылка, я.комната, запрос);
  if (годная) комнаты.запомнитьСсылку(я.комната, я.ктоЯ, годная);
}

/** Отправить письмо ленты. Ответ Telegram (и 403 в нём) разбирает сама лента. */
function отправитьПисьмоЛенты(письмо) {
  return спроситьTelegram('sendMessage', {
    chat_id: письмо.chat_id,
    text: письмо.text,
    link_preview_options: { is_disabled: true },
    reply_markup: письмо.reply_markup
  });
}

/**
 * Событие стола → лента. Имя вызвавшего подменяем на имя из подписи
 * Telegram, если оно известно: игровое имя человек пишет сам, и назваться
 * в письме от бота «Поддержкой Telegram» мог бы кто угодно.
 */
function событиеСтолаВЛенту(данные) {
  if (!умеемГотовитьПриглашения() || !данные) return;
  const имя = данные.ктоНомер ? имяИзПодписиПоНомеру.get(данные.ктоНомер) : '';
  лента.событие(имя ? Object.assign({}, данные, { ктоИмя: имя }) : данные);
}

