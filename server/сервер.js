/** Создать сервер. Отдельной функцией — чтобы проверка могла поднять свой. */
function создатьСервер() {
  /* Учёт приглашений читаем сразу при старте: комнаты прошлого запуска
     пропали вместе с его памятью, и их незакрытые приглашения закрываются
     событием «комнатаПотеряна» (см. server/приглашения.js). */
  приглашения.загрузить();
  const сервер = http.createServer(function (запрос, ответ) {
    обработать(запрос, ответ).catch(function (сбой) {
      // Ни одна ошибка не должна ронять сервер: партии живут в памяти,
      // упавший сервер — это все партии сразу.
      ошибка(ответ, 500, 'Сервер не смог обработать запрос');
      console.error('Ошибка при обработке запроса:', сбой.message);
    });
  });

  /* --- Сроки: почему они считаются от первого байта, а не от соединения ---

     Раньше здесь стояли встроенные сроки Node (headersTimeout и
     requestTimeout). Они считают время от того мига, когда соединение
     открыли, — даже если по нему ещё ни разу ничего не сказали. И это
     оказалось причиной, по которой у нас каждый день падали туннели.

     Дело вот в чём. Туннель (программа, которая даёт домашнему
     компьютеру адрес в интернете) заранее открывает к нам десяток
     соединений и держит их пустыми — про запас, чтобы отвечать быстрее.
     Для Node это выглядело как «запрос начали и бросили», и через
     полминуты-минуту он отвечал таким соединениям «408, закрываю».
     Замерено: пустое соединение получало отказ через 50 секунд. Туннель
     от этого терял свои соединения одно за другим и в конце концов
     умирал совсем — а мы списывали это на «бесплатные сервисы
     нестабильны». Для человека это выглядело так: открыл игру после
     паузы, нажал «Создать игру» — «сервер не ответил», нажал ещё раз —
     снова, и только с третьего раза выходило.

     Поэтому встроенные сроки выключены (ноль), а вместо них — свой
     сторож ниже. Он делает ровно то же самое, но отсчёт начинает
     с первого байта настоящего запроса. Пустое соединение живёт сколько
     угодно, а начатый и брошенный запрос убирается как и прежде. */
  сервер.headersTimeout = 0;
  сервер.requestTimeout = 0;
  сервер.keepAliveTimeout = длительностьОпроса + 10 * 1000;

  /* Сколько даём на то, чтобы начатый запрос дошёл целиком и получил
     ответ. Число то же самое, что стояло в прежнем requestTimeout, —
     мы поменяли момент начала отсчёта, а не строгость.

     Почему столько. Дольше всего у нас длится не сам запрос (он
     крошечный), а наш ответ на «что нового»: сервер придерживает его до
     конца опроса. Значит, срок обязан быть больше опроса, иначе сторож
     обрывал бы собственный длинный опрос на полуслове — игрок получал
     бы разрыв связи ровно в тот миг, когда ждёт хода друга. Плюс
     полминуты запаса на медленную сеть и на то, что ответ ещё надо
     дописать в соединение.

     Меньше минуты ставить нельзя: при обычном опросе в 25 секунд запас
     съедается почти целиком. Больше — тоже незачем: брошенный запрос
     будет дольше занимать место. */
  const СРОК_НА_ЗАПРОС = Math.max(60 * 1000, длительностьОпроса + 30 * 1000);

  сервер.on('connection', function (соединение) {
    let сторож = null;

    function снятьСторожа() {
      if (сторож === null) return;
      clearTimeout(сторож);
      сторож = null;
    }

    /* Пошли данные — значит запрос начался, и с этого мига он обязан
       уложиться в срок. Пока данных нет, соединение нам ничего не стоит,
       и торопить его не за что. */
    соединение.on('data', function () {
      if (сторож !== null) return;      // срок уже идёт, второй не заводим
      сторож = setTimeout(function () {
        сторож = null;
        соединение.destroy();
      }, СРОК_НА_ЗАПРОС);
    });

    // Ответ ушёл — запрос кончился, срок больше не нужен. Следующий
    // запрос по этому же соединению заведёт себе новый.
    соединение.on('ответ-ушёл', снятьСторожа);
    соединение.on('close', снятьСторожа);
  });

  /* Мостик от ответа к соединению: сторож живёт при соединении и о самих
     запросах ничего не знает, поэтому конец каждого ответа объявляем ему
     сами. */
  сервер.on('request', function (запрос, ответ) {
    ответ.on('finish', function () {
      if (запрос.socket) запрос.socket.emit('ответ-ушёл');
    });
  });

  return сервер;
}

/* Слушаем только свой компьютер. Без второго довода listen открывает порт
   на всех сетевых входах, а брандмауэр машины пускает node на входящие:
   сосед по Wi-Fi достучался бы до сервера напрямую и подставил бы любой
   заголовок Host — а по Host сервер проверяет ссылки за стол (хвостВедётСюда).
   Снаружи к серверу ходят только через туннель cloudflared, а он приходит
   на http://127.0.0.1:порт. Никто в проекте на доступ по сети не рассчитывает. */
const АДРЕС_ПРОСЛУШКИ = '127.0.0.1';

/**
 * Поднять сервер. Вторым доводом можно задать длительность опроса
 * в миллисекундах — если его нет, остаётся то, что выбрано при запуске.
 */
function запустить(порт, опросМс) {
  if (опросМс !== undefined && опросМс !== null) длительностьОпроса = опросМс;

  const сервер = создатьСервер();
  комнаты.запуститьУборку();
  /* Настоящий сервер с диском ключ уже подготовил (и при нужде создал)
     до запуска; здесь — только прочитать готовый, не создавая. */
  if (ключШтаба === null) подготовитьКлючШтаба(false);

  /* Имя бота спрашиваем у Telegram сразу при старте, не дожидаясь первого
     зова: getMe может идти до пяти секунд, а зовущий на кнопке «Позвать»
     ждёт куда меньше. Раз имяНашегоБота() запоминает ответ, все зовы после
     старта берут его из памяти мгновенно. Не ответил — не беда, тот же
     запрос повторится при первом зове, как и раньше. */
  if (умеемГотовитьПриглашения()) {
    имяНашегоБота().catch(function () {});
  }

  const секундОпроса = длительностьОпроса / 1000;
  // Чтобы совет «запустите заново» не отнимал уже сделанную настройку.
  const хвостСНастройкой = длительностьОпроса === ОПРОС_ПО_УМОЛЧАНИЮ ? '' : ' ' + секундОпроса;

  сервер.on('error', function (сбой) {
    if (сбой.code === 'EADDRINUSE') {
      console.error('Порт ' + порт + ' уже занят: на нём работает другая программа ' +
        'или вторая копия этого сервера.');
      console.error('Запустите с другим номером, например: node server/сервер.js ' +
        (порт + 25) + хвостСНастройкой);
    } else {
      console.error('Сервер не запустился:', сбой.message);
    }
    process.exit(1);
  });

  сервер.listen(порт, АДРЕС_ПРОСЛУШКИ, function () {
    console.log('Сервер игры вдвоём работает на порту ' + порт +
      '. Ответа на «что нового» ждём до ' + секундОпроса + ' с' +
      (длительностьОпроса === ОПРОС_ПО_УМОЛЧАНИЮ
        ? ' (как обычно).'
        : ' (обычно ' + ОПРОС_ПО_УМОЛЧАНИЮ / 1000 + ' с — укорочено под туннель).'));
    console.log('Проверить: http://127.0.0.1:' + порт + '/здоровье');
    console.log('Остановить — Ctrl+C. Комнаты хранятся в памяти: ' +
      'после перезапуска начатые партии пропадут.');
  });

  return сервер;
}

// Запускаемся, только если файл запустили напрямую. Если его подключили
// из проверки — она поднимет сервер сама, на своём порту.
if (require.main === module) {
  const сказанное = разобратьАргументы(process.argv.slice(2));

  /* Память на диске — только у настоящего сервера. Проверки подключают
     этот файл как модуль и поднимают сервер сами; их партии и выдуманные
     игроки считаются в памяти и на диск не попадают. Проверочный сервер,
     поднятый напрямую, отключает запись словом «--без-памяти». */
  if (сказанное.безПамяти) {
    console.log('Запущен без памяти: знакомые и статистика на диск не пишутся.');
  } else {
    /* Сказать вслух, если данные уведены в сторону. Тихо писать не туда —
       худшее, что может делать сервер с чужими именами: пропажу заметят
       через недели. */
    if (гдеДанные.папкаУведена()) {
      console.log('Данные игры уведены в папку: ' + гдеДанные.папка());
    }
    /* Копию снимаем ЗДЕСЬ — до того, как хоть кто-то начнёт писать.
       Скопированный в середине записи файл выглядит целым, а внутри
       у него обрывок, и надеяться на такую копию хуже, чем не иметь её. */
    копииДанных.снятьКопию();
    console.log(копииДанных.словами());
    знакомые.включитьЗапись();
    друзья.включитьЗапись();
    неЗвать.включитьЗапись();
    статистика.включитьЗапись();
    приглашения.включитьЗапись();
    рейтинг.включитьЗапись();
    раздачаДня.включитьЗапись();
    посещения = учётПосещений.создать({ файл: гдеДанные.файл('посещения.json') });
    популярность = require('./популярность.js').создать(гдеДанные.файл('популярность.json'));
    подготовитьКлючШтаба(true);
  }

  запустить(выбратьПорт(сказанное.порт), выбратьДлительностьОпроса(сказанное.опрос));

  /* Останавливают сервер здесь часто, а знакомства пишутся на диск не сразу,
     а через несколько секунд после последней раздачи (чтобы не бить по диску
     на каждый чих). Без этих строк Ctrl+C сразу после начала партии терял бы
     свежее знакомство. Ставим сторожа только при прямом запуске: когда файл
     подключает проверка, лезть в остановку чужой программы нельзя. */
  for (const сигнал of ['SIGINT', 'SIGTERM']) {
    process.on(сигнал, function () {
      знакомые.дописать();
      друзья.дописать();
      неЗвать.дописать();
      статистика.дописать();
      приглашения.дописать();
      рейтинг.дописать();
      раздачаДня.дописать();
      посещения.дописать();
      популярность.дописать();
      process.exit(0);
    });
  }
}

