'use strict';

/* =====================================================================
   Раздача дня: кто как сыграл одну и ту же раздачу.

   Зачем. Игра раз в день предлагает «раздачу дня»: колода перемешана
   по зерну из даты, поэтому у всех, кто нажал сегодня, одни и те же
   карты. Смысл появляется, когда свой итог можно сравнить с остальными:
   «Сегодня эту раздачу выиграли 12 из 30, вы на 4-м месте». Сравнивать
   есть кому только здесь — на сервере, куда все и приносят результат.

   Что храним. По дням — кто (номер Telegram из подписи), чем кончилось
   и за сколько ходов. Номер нужен ради двух вещей: «один человек — один
   результат в день» и «моё место». Наружу номера не уходят никогда:
   ответ — одни числа. Имена не храним вовсе: для «сколько выиграли»
   и «моё место» они не нужны.

   Место считается так: победители впереди проигравших, ничья между ними;
   среди победителей лучше тот, кто уложился в меньше ходов; среди
   проигравших — кто продержался дольше. Место = 1 + число тех, кто строго
   лучше, поэтому одинаковые результаты делят одно место.

   Хранится 60 дней, тем же способом, что знакомые и статистика:
   в server/данные, отложенно, через временный файл, и только у сервера,
   запущенного напрямую (см. включитьЗапись).
   ===================================================================== */

const fs = require('fs');
const path = require('path');

/* Где лежат данные, спрашиваем при каждом обращении — у одного
   места на весь сервер (см. server/папка-данных.js). Своей копии пути
   здесь нет нарочно: пока он был зашит тут, проверки из tests/ писали
   прямо в боевую папку и однажды стёрли настоящие данные владельца. */
const гдеДанные = require('./папка-данных.js');

/** Папка с данными прямо сейчас. */
function папка() { return гдеДанные.папка(); }

/** Наш файл памяти. */
function файл() { return гдеДанные.файл('раздача-дня.json'); }

/** Временный файл, в который пишем перед переименованием. */
function файлПокаПишем() { return файл() + '.пишем'; }

const ХРАНИМ_ДНЕЙ = 60;
const ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ = 5000;

/* Какие исходы принимаем. Вдвоём в дурака бывает и ничья — оба вышли
   разом; прятать её в «поражение» было бы неправдой. */
const ИСХОДЫ = ['победа', 'ничья', 'поражение'];

/* Сколько ходов бывает в партии. Ноль — не партия; больше тысячи —
   не дурак. Числа вне этих границ — мусор, а не результат. */
const ХОДОВ_НЕ_МЕНЬШЕ = 1;
const ХОДОВ_НЕ_БОЛЬШЕ = 1000;

/* День пишем тот, что назвала игра — по часам телефона, — но не дальше
   одного дня от серверного: часовые пояса дают разницу в сутки, а больше
   разницы честной не бывает — это уже запись в будущее или в прошлое. */
const РАЗНИЦА_ДНЕЙ_ДОПУСТИМА = 1;

/* Ключ дня → Map<номер, { исход, ходов }>. */
const дни = new Map();

let естьЧтоЗаписать = false;
let таймерЗаписи = null;
let ужеЗагрузили = false;
let записьРазрешена = false;

function включитьЗапись() {
  записьРазрешена = true;
}

/** «2026-09-07» по местному времени сервера. */
function ключДня(время) {
  const дата = new Date(время === undefined ? Date.now() : время);
  const месяц = String(дата.getMonth() + 1).padStart(2, '0');
  const число = String(дата.getDate()).padStart(2, '0');
  return дата.getFullYear() + '-' + месяц + '-' + число;
}

function ключДняНазад(сколькоНазад) {
  const дата = new Date();
  дата.setDate(дата.getDate() - сколькоНазад);
  return ключДня(дата.getTime());
}

/** Похоже ли на ключ дня, и настоящая ли это дата. */
function этоДень(что) {
  if (typeof что !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(что)) return false;
  const дата = new Date(что + 'T00:00:00');
  return !Number.isNaN(дата.getTime()) && ключДня(дата.getTime()) === что;
}

/** Сколько дней между двумя ключами (по модулю). */
function разницаДней(один, другой) {
  const а = new Date(один + 'T00:00:00').getTime();
  const б = new Date(другой + 'T00:00:00').getTime();
  return Math.round(Math.abs(а - б) / (24 * 60 * 60 * 1000));
}

function этоНомерИгрока(номер) {
  return Number.isInteger(номер) && номер > 0;
}

/* ---------------------------------------------------------------------
   Чтение и запись файла
   --------------------------------------------------------------------- */

function загрузить() {
  ужеЗагрузили = true;
  let текст = '';
  try {
    текст = fs.readFileSync(файл(), 'utf8');
  } catch (сбой) {
    return;
  }
  let прочитанное = null;
  try {
    прочитанное = JSON.parse(текст);
  } catch (сбой) {
    return;
  }
  if (!прочитанное || !Array.isArray(прочитанное.дни)) return;

  for (const запись of прочитанное.дни) {
    if (!запись || !этоДень(запись.день) || !Array.isArray(запись.результаты)) continue;
    const день = new Map();
    for (const итог of запись.результаты) {
      if (!итог) continue;
      const номер = Number(итог.номер);
      const ходов = Number(итог.ходов);
      if (!этоНомерИгрока(номер) || ИСХОДЫ.indexOf(итог.исход) === -1) continue;
      if (!Number.isInteger(ходов) || ходов < ХОДОВ_НЕ_МЕНЬШЕ || ходов > ХОДОВ_НЕ_БОЛЬШЕ) continue;
      день.set(номер, { исход: итог.исход, ходов: ходов });
    }
    дни.set(запись.день, день);
  }
  прибраться();
}

function записатьСейчас() {
  естьЧтоЗаписать = false;
  const список = [];
  for (const [ключ, день] of дни) {
    const результаты = [];
    for (const [номер, итог] of день) {
      результаты.push({ номер: номер, исход: итог.исход, ходов: итог.ходов });
    }
    список.push({ день: ключ, результаты: результаты });
  }
  try {
    fs.mkdirSync(папка(), { recursive: true });
    fs.writeFileSync(файлПокаПишем(), JSON.stringify({ дни: список }), 'utf8');
    fs.renameSync(файлПокаПишем(), файл());
  } catch (сбой) {
    /* Не записалось — останется в памяти до следующей попытки. */
  }
}

function записатьПогодя() {
  if (!записьРазрешена) return;
  естьЧтоЗаписать = true;
  if (таймерЗаписи !== null) return;
  таймерЗаписи = setTimeout(function () {
    таймерЗаписи = null;
    if (естьЧтоЗаписать) записатьСейчас();
  }, ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ);
  if (таймерЗаписи.unref) таймерЗаписи.unref();
}

function дописать() {
  if (таймерЗаписи !== null) {
    clearTimeout(таймерЗаписи);
    таймерЗаписи = null;
  }
  if (естьЧтоЗаписать) записатьСейчас();
}

function прибраться() {
  const самыйСтарый = ключДняНазад(ХРАНИМ_ДНЕЙ - 1);
  for (const ключ of дни.keys()) {
    if (ключ < самыйСтарый) дни.delete(ключ);
  }
}

/* ---------------------------------------------------------------------
   Сам счёт
   --------------------------------------------------------------------- */

/**
 * Записать результат. Ответ — { ок, причина }: причина словами, чтобы
 * игра могла показать её человеку как есть.
 */
function записать(день, номер, исход, ходов) {
  if (!ужеЗагрузили) загрузить();
  if (!этоНомерИгрока(номер)) return { ок: false, причина: 'Результат записывается только из Telegram' };
  if (!этоДень(день)) return { ок: false, причина: 'Не понял, за какой день результат' };
  if (разницаДней(день, ключДня()) > РАЗНИЦА_ДНЕЙ_ДОПУСТИМА) {
    return { ок: false, причина: 'Этот день слишком далёк от сегодняшнего' };
  }
  if (ИСХОДЫ.indexOf(исход) === -1) return { ок: false, причина: 'Не понял, чем кончилась партия' };
  const число = Number(ходов);
  if (!Number.isInteger(число) || число < ХОДОВ_НЕ_МЕНЬШЕ || число > ХОДОВ_НЕ_БОЛЬШЕ) {
    return { ок: false, причина: 'Не понял, сколько было ходов' };
  }

  let результаты = дни.get(день);
  if (!результаты) {
    результаты = new Map();
    дни.set(день, результаты);
    прибраться();
  }
  if (результаты.has(номер)) {
    return { ок: false, причина: 'Раздачу дня можно сыграть один раз — ваш результат уже записан' };
  }
  результаты.set(номер, { исход: исход, ходов: число });
  записатьПогодя();
  return { ок: true };
}

/** Насколько результат хорош: больше — лучше. Нужно только для сравнения. */
function сила(итог) {
  if (итог.исход === 'победа') return 3 * ХОДОВ_НЕ_БОЛЬШЕ + (ХОДОВ_НЕ_БОЛЬШЕ - итог.ходов);
  if (итог.исход === 'ничья') return 2 * ХОДОВ_НЕ_БОЛЬШЕ;
  return итог.ходов;    // проиграл — но чем дольше держался, тем лучше
}

/**
 * Сводка за день. Номер игрока — необязателен: без него «моё место» пусто.
 * Собирается поле за полем: в ответе одни числа, номеров нет.
 */
function сводка(день, номер) {
  if (!ужеЗагрузили) загрузить();
  const ответ = {
    день: этоДень(день) ? день : ключДня(),
    сыграли: 0,
    выиграли: 0,
    среднийХодПобедителей: null,
    моёМесто: null
  };
  const результаты = дни.get(ответ.день);
  if (!результаты) return ответ;

  let ходовПобедителей = 0;
  for (const итог of результаты.values()) {
    ответ.сыграли++;
    if (итог.исход === 'победа') {
      ответ.выиграли++;
      ходовПобедителей += итог.ходов;
    }
  }
  if (ответ.выиграли > 0) {
    ответ.среднийХодПобедителей = Math.round(ходовПобедителей / ответ.выиграли);
  }

  const мой = этоНомерИгрока(номер) ? результаты.get(номер) : null;
  if (мой) {
    let лучших = 0;
    const моя = сила(мой);
    for (const итог of результаты.values()) {
      if (сила(итог) > моя) лучших++;
    }
    ответ.моёМесто = лучших + 1;
  }
  return ответ;
}

/** Забыть всё (нужно проверкам). */
function забытьВсё() {
  дни.clear();
  ужеЗагрузили = true;
  записатьПогодя();
}

module.exports = {
  ХРАНИМ_ДНЕЙ: ХРАНИМ_ДНЕЙ,
  ИСХОДЫ: ИСХОДЫ,
  /* Путь к файлу — вопросом, а не значением: он зависит от того,
     куда уведена папка данных, и меняться может между вызовами. */
  get ФАЙЛ() { return файл(); },
  ключДня: ключДня,
  этоДень: этоДень,
  включитьЗапись: включитьЗапись,
  загрузить: загрузить,
  записать: записать,
  сводка: сводка,
  забытьВсё: забытьВсё,
  дописать: дописать
};
