/* =====================================================================
   ЛЕНТА БОТА: письма игроку о событиях стола (кроме зова знакомого —
   тот шлёт server/сервер.js сам, без этого модуля).

   Зачем это нужно. Игрок свернул приложение или закрыл вкладку, а за
   его столом что-то произошло: подсел новый человек, стол собрался,
   партия началась, кто-то зовёт сыграть ещё раз. Без письма человек
   узнает об этом, только когда сам вернётся и посмотрит — а стол к
   тому времени может уже разойтись. Лента дублирует такие события
   письмом от бота, ровно как обычный зов знакомого.

   Модуль ЧИСТЫЙ: сети не открывает, файлов не читает и не пишет,
   про Telegram ничего не знает напрямую. Всё внешнее — через
   подключить(): кто и как в итоге пишет письмо, кто помнит отказы,
   кто скажет, жив ли ещё стол. Так его можно проверить одним node-
   скриптом и подключить туда, где он на самом деле нужен (server/
   сервер.js, этап 3 общего плана), без единой правки этого файла.

   Четыре события и их письма — таблица §2 плана штаб/план-лента-бота.md:
     2  — кто-то сел за стол: всем, кто уже сидел, кроме вошедшего.
     3а — стол на двоих, второй сел, игра началась сразу же.
     3б — стол-компания собрался полностью: хозяину.
     3в — хозяин нажал «Начать»: всем, кроме хозяина.
     4  — кто-то предложил сыграть ещё: тем, кто ещё не согласился.
   Событие «1» (зов знакомого) сюда не входит — оно как было в
   server/сервер.js, так там и остаётся.

   Отступление от буквального списка полей события, ЧЕСТНО ЗАПИСАННОЕ
   ЗДЕСЬ: чтобы собрать текст «(2 из 4)» для события 2 и «все 4 места
   заняты» для события 3б, модулю нужно знать число занятых и все
   мест за столом. Ни таблица, ни короткое описание API эти поля не
   называют явно, поэтому событие() принимает необязательные
   занятоМест/всегоМест; если их не прислали, число занятых грубо
   считается по длине списка «кому» (кому + сам вошедший), а «всего»
   принимается равным занятому — это запасной случай на будущее,
   боевой вызов (этап 2/3) обязан присылать оба числа по-настоящему.

   Поле хозяинНомер — тоже расширение сверх буквального списка полей:
   единственная причина отфильтровать адресата — «это тот, кто вызвал
   событие» (ктоНомер). Но у события 3б адресат — хозяин, а вызвал
   событие человек, занявший последнее место, так что совпадения не
   бывает. Единственный случай, когда номер адресата и ктоНомер могут
   совпасть законно, — хозяин сам оказался тем, кто заполнил стол.
   хозяинНомер существует для этого редкого случая: если номер
   адресата равен хозяинНомер, самофильтр по ктоНомер его не выкинет.
   Исключение работает ТОЛЬКО для события 3б — у остальных типов
   самому себе никогда не пишем, даже если номера случайно совпали
   (замечание ревьюера: границу не размывать на всю ленту).
   ===================================================================== */

/* ---------------------------------------------------------------------
   Название игры в письме — два разных грамматических случая:
   «за вашим столом в X» (событие 2) и «партия в X» (события 3а, 3в).
   У шашек, нард и шахмат оба случая совпадают со словарным словом,
   у дурака — нет («подкидного дурака» при «за столом», «дурака» при
   «партия»). Слова берутся из общей таблицы server/названия.js — там же,
   где их берёт письмо знакомому, так новые игры не подменяются дураком.
   Словарь закрытый: игра, которой в нём нет, читается как дурак —
   подставлять сюда что-то пришедшее со стороны нельзя.

   Имя игрока рода не знает (Telegram его не сообщает), поэтому ни в
   одном тексте письма нет глагола прошедшего времени, согласуемого
   с именем («сел»/«села», «пришёл»/«пришла» и т.п.) — только настоящее
   время («предлагает») или конструкции без глагола при имени вовсе
   («Лена — за вашим столом»). Меняя тексты ниже, это правило не
   нарушать — иначе снова получится «Лена сел» (замечание владельца).
   --------------------------------------------------------------------- */
const названия = require('./названия.js');

function играДляЗаСтолом(игра) { return названия.словаИгры(игра).заСтолом; }
function играДляПартии(игра) { return названия.словаИгры(игра).партия; }

/** Русское слово «место»/«места»/«мест» под число, для «все N ... заняты». */
function словоМесто(число) {
  const остаток10 = число % 10;
  const остаток100 = число % 100;
  if (остаток10 === 1 && остаток100 !== 11) return 'место';
  if (остаток10 >= 2 && остаток10 <= 4 && (остаток100 < 12 || остаток100 > 14)) return 'места';
  return 'мест';
}

/* Сколько знаков имени показываем в письме — как в письме знакомому
   (ИМЯ_В_ПИСЬМЕ в сервер.js). Управляющие знаки вычищаем: имя стоит
   первым словом письма, и подделывать им вид письма нельзя. */
const ИМЯ_В_ПИСЬМЕ = 32;

function имяДляПисьма(имя) {
  const чистое = String(имя || '').replace(/[\s\x00-\x1f]+/g, ' ').trim();
  return чистое.slice(0, ИМЯ_В_ПИСЬМЕ) || 'Игрок';
}

/** Числа занятых/всех мест — из явных полей события или, если их нет,
 *  грубым запасным счётом по списку адресатов (см. отступление вверху). */
function числоМест(данные) {
  const кому = Array.isArray(данные.кому) ? данные.кому : [];
  const запасноеЗанято = кому.length + 1;   // адресаты + сам вошедший/начавший
  const занято = Number.isFinite(Number(данные.занятоМест)) && данные.занятоМест !== undefined
    ? Number(данные.занятоМест) : запасноеЗанято;
  const всего = Number.isFinite(Number(данные.всегоМест)) && данные.всегоМест !== undefined
    ? Number(данные.всегоМест) : занято;
  return { занято: занято, всего: всего };
}

/**
 * Собрать текст письма под конкретное событие. null — если событие
 * ленте не знакомо (событие «1» и всё прочее сюда не попадает).
 */
function текстПисьма(данные) {
  const имя = имяДляПисьма(данные.ктоИмя);
  switch (данные.что) {
    case '2': {
      const мест = числоМест(данные);
      // Без «сел»/«села»: конструкция «имя — за вашим столом» верна для
      // любого рода имени, глагола-сказуемого при имени тут нет вовсе.
      return имя + ' — за вашим столом в ' + играДляЗаСтолом(данные.игра) +
        ' (' + мест.занято + ' из ' + мест.всего + '). Откройте игру, чтобы не пропустить начало.';
    }
    case '3а':
      // Без «ваш ход» (по решению владельца) и без «сел» — та же
      // безглагольная конструкция «имя за вашим столом», что у события 2.
      return имя + ' за вашим столом — партия в ' + играДляПартии(данные.игра) + ' началась.';
    case '3б': {
      const мест = числоМест(данные);
      return 'Стол собрался: все ' + мест.всего + ' ' + словоМесто(мест.всего) +
        ' заняты. Нажмите «Начать».';
    }
    case '3в':
      return 'Хозяин стола начал партию в ' + играДляПартии(данные.игра) + ' — вас ждут.';
    case '4':
      return имя + ' предлагает сыграть ещё одну партию. Откройте стол, чтобы согласиться.';
    default:
      return null;
  }
}

/* Слово в кнопке отказа — то же самое, что у письма знакомому
   (ОТКАЗ_ОТ_ЗОВОВ в сервер.js): бот слушает нажатие по этому слову,
   разводить два разных слова для двух видов писем незачем. */
const ОТКАЗ_ОТ_ЗОВОВ = 'не-звать';

/** Кнопки письма: «Открыть стол» — только если ссылку прислали, и
 *  всегда «Не звать меня». */
function кнопкиПисьма(ссылка) {
  const строки = [];
  if (ссылка) строки.push([{ text: 'Открыть стол', url: ссылка }]);
  строки.push([{ text: 'Не звать меня', callback_data: ОТКАЗ_ОТ_ЗОВОВ }]);
  return { inline_keyboard: строки };
}

/**
 * Собрать письмо целиком: { текст, кнопки } или null для неизвестного
 * события. Вынесено отдельной функцией и экспортировано — проверки
 * сверяют письмо тем же способом, каким его собирает сама лента,
 * вторую копию текста заводить не надо (см. tests/лента-бота.js).
 */
function собратьПисьмо(данные) {
  const текст = текстПисьма(данные);
  if (текст === null) return null;
  return { текст: текст, кнопки: кнопкиПисьма(данные.ссылка) };
}

/* ---------------------------------------------------------------------
   Зависимости, подставляемые снаружи. Пока подключить() не вызвали
   (или отправить не задан), событие() ничего не делает — это нормальное
   состояние для «модуль есть, но никуда не подключён» из этапа 1.
   --------------------------------------------------------------------- */
let отправитьВнешний = null;
let почемуНеЗватьВнешний = null;
let запретитьВнешний = null;
let ещёЗаСтоломВнешний = null;
let уЭкранаВнешний = null;
let сейчасФункция = Date.now;
let отложитьФункция = function (дело, мс) { return setTimeout(дело, мс); };

/**
 * Подключить ленту к настоящему миру.
 *   отправить(тело)        — послать письмо в Telegram, вернуть (или
 *                             пообещать) ответ вида { ok, error_code }.
 *   почемуНеЗвать(номер)    — '' | 'сам' | 'ботНеПишет'.
 *   запретить(номер, причина) — запомнить отказ (вызывается при 403).
 *   ещёЗаСтолом(код, номер) — сидит ли этот номер прямо сейчас за этим
 *                             столом (для перепроверки перед отложенной
 *                             отправкой писем 2, 3а и 3б — и вызвавшего
 *                             событие, и каждого адресата).
 *   уЭкрана(код, номер)     — держит ли этот номер прямо сейчас открытый
 *                             экран стола (для той же перепроверки: если
 *                             человек уже вернулся, письмо ему не нужно,
 *                             и лимит на него не тратится). Необязательна:
 *                             если не передана, лента доверяет отметке
 *                             наЭкране из самого события, как раньше.
 *   сейчас, отложить        — подменяемые часы; по умолчанию Date.now
 *                             и обычный setTimeout. Проверки подставляют
 *                             свои, чтобы не ждать реальных секунд.
 */
function подключить(зависимости) {
  зависимости = зависимости || {};
  отправитьВнешний = typeof зависимости.отправить === 'function' ? зависимости.отправить : null;
  почемуНеЗватьВнешний = typeof зависимости.почемуНеЗвать === 'function' ? зависимости.почемуНеЗвать : null;
  запретитьВнешний = typeof зависимости.запретить === 'function' ? зависимости.запретить : null;
  ещёЗаСтоломВнешний = typeof зависимости.ещёЗаСтолом === 'function' ? зависимости.ещёЗаСтолом : null;
  уЭкранаВнешний = typeof зависимости.уЭкрана === 'function' ? зависимости.уЭкрана : null;
  сейчасФункция = typeof зависимости.сейчас === 'function' ? зависимости.сейчас : Date.now;
  отложитьФункция = typeof зависимости.отложить === 'function'
    ? зависимости.отложить
    : function (дело, мс) { return setTimeout(дело, мс); };
}

/* ---------------------------------------------------------------------
   Пределы: сколько писем и как часто.
   --------------------------------------------------------------------- */
const ПРЕДЕЛ_ТИПА = 60 * 1000;      // один тип одному адресату на один стол — не чаще раза в это время
const ПРЕДЕЛ_В_ЧАС = 10;            // писем ленты одному человеку — не больше за час
const ЧАС = 60 * 60 * 1000;
const ПОТОЛОК_ПАМЯТИ = 2000;
const ЗАДЕРЖКА_ПОСАДКИ = 5000;      // письма 2, 3а и 3б откладываются на это время

const когдаТипу = new Map();        // «тип:номер:код» → когда последний раз слали
const писемЧеловеку = new Map();    // номер → [времена писем за последний час]

/** Выбросить из памяти пределов старьё и лишнее сверх потолка — как
 *  прибратьЗовы в сервер.js, только своя пара карт. */
function подрезатьПамять(сейчас) {
  if (когдаТипу.size > ПОТОЛОК_ПАМЯТИ) {
    for (const [ключ, когда] of когдаТипу) {
      if (сейчас - когда >= ЧАС) когдаТипу.delete(ключ);
    }
    if (когдаТипу.size > ПОТОЛОК_ПАМЯТИ) {
      const порядок = Array.from(когдаТипу.entries()).sort(function (а, б) { return а[1] - б[1]; });
      const лишних = когдаТипу.size - ПОТОЛОК_ПАМЯТИ;
      for (let счёт = 0; счёт < лишних; счёт++) когдаТипу.delete(порядок[счёт][0]);
    }
  }
  if (писемЧеловеку.size > ПОТОЛОК_ПАМЯТИ) {
    for (const [номер, времена] of писемЧеловеку) {
      const свежие = времена.filter(function (в) { return сейчас - в < ЧАС; });
      if (свежие.length) писемЧеловеку.set(номер, свежие);
      else писемЧеловеку.delete(номер);
    }
    if (писемЧеловеку.size > ПОТОЛОК_ПАМЯТИ) {
      const номера = Array.from(писемЧеловеку.keys());
      const лишних = писемЧеловеку.size - ПОТОЛОК_ПАМЯТИ;
      for (let счёт = 0; счёт < лишних; счёт++) писемЧеловеку.delete(номера[счёт]);
    }
  }
}

/** Можно ли слать: и по пределу типа на этот стол, и по пределу в час.
 *  Считаем попытки, а не удачи (как записатьЗов в сервер.js) — метим
 *  оба предела сразу, как только решили слать, не дожидаясь ответа
 *  Telegram. Важно: вызывается в момент НАСТОЯЩЕЙ отправки (внутри
 *  выполнить(), после всех перепроверок), а не при постановке письма
 *  в очередь — иначе письмо, которое потом отменит перепроверка
 *  (ушёл со стола / уже у экрана), «съест» лимит как призрак. */
function можноПослать(тип, номер, код, сейчас) {
  подрезатьПамять(сейчас);

  const ключТипа = тип + ':' + номер + ':' + код;
  const последнееПоТипу = когдаТипу.get(ключТипа);
  if (последнееПоТипу !== undefined && сейчас - последнееПоТипу < ПРЕДЕЛ_ТИПА) return false;

  const прежние = писемЧеловеку.get(номер) || [];
  const свежие = прежние.filter(function (в) { return сейчас - в < ЧАС; });
  if (свежие.length >= ПРЕДЕЛ_В_ЧАС) {
    писемЧеловеку.set(номер, свежие);
    return false;
  }

  когдаТипу.set(ключТипа, сейчас);
  свежие.push(сейчас);
  писемЧеловеку.set(номер, свежие);
  return true;
}

/* ---------------------------------------------------------------------
   Выбор адресатов.
   --------------------------------------------------------------------- */

/** Можно ли вообще писать этому человеку: не у экрана (по отметке
 *  самого события), номер настоящий, не сам вызвавший (кроме хозяина
 *  у события 3б, см. отступление в шапке файла — у остальных типов
 *  самому себе не пишем никогда), без запрета «сам»/«ботНеПишет». */
function можноПисать(человек, ктоНомер, хозяинНомер, тип) {
  if (!человек || человек.наЭкране) return false;
  const номер = Number(человек.номер);
  if (!Number.isInteger(номер) || номер <= 0) return false;

  const этоХозяин = тип === '3б' && Number.isInteger(хозяинНомер) && хозяинНомер > 0 && номер === хозяинНомер;
  if (номер === ктоНомер && !этоХозяин) return false;

  if (почемуНеЗватьВнешний) {
    const запрет = почемуНеЗватьВнешний(номер);
    if (запрет === 'сам' || запрет === 'ботНеПишет') return false;
  }
  return true;
}

/** Отправить письмо прямо сейчас одному человеку. Сбой — молча: в
 *  словах Telegram может быть что угодно, вплоть до адреса с токеном,
 *  пересказывать их некому. 403 — «бот не может писать» — запоминаем
 *  через запретить(номер, 'ботНеПишет'), ровно как делает сервер.js
 *  для зова знакомого. */
function послатьТеперь(номер, письмо) {
  if (!отправитьВнешний) return;
  Promise.resolve(отправитьВнешний({
    chat_id: номер,
    text: письмо.текст,
    reply_markup: письмо.кнопки
  })).then(function (итог) {
    if (итог && Number(итог.error_code) === 403 && запретитьВнешний) {
      запретитьВнешний(номер, 'ботНеПишет');
    }
  }).catch(function () {
    /* сбой отправки — молча, как договорено в плане */
  });
}

/**
 * Событие на столе — рождается там, где оно случилось (этап 2 плана
 * подключит сюда server/комнаты.js), и превращается в письма тем, кому
 * это нужно знать.
 *
 *   что        — '2' | '3а' | '3б' | '3в' | '4' (другое — молча пропускаем).
 *   игра       — слово игры из server/названия.js ('дурак', 'нарды', …).
 *   код        — код стола (для пределов и перепроверки «ещё за столом»).
 *   ктоИмя     — имя того, кто вызвал событие (для текста писем 2, 3а, 4).
 *   ктоНомер   — его номер в Telegram (для перепроверки и самофильтра).
 *   кому       — [{ номер, наЭкране }] — кандидаты в адресаты.
 *   ссылка     — ссылка за стол для кнопки «Открыть стол» (не обязательна).
 *   хозяинНомер — см. отступление в шапке файла (не обязателен).
 *   занятоМест, всегоМест — см. отступление в шапке файла (не обязательны).
 */
function событие(данные) {
  данные = данные || {};
  if (!отправитьВнешний) return;         // лента не подключена — тихо ничего не делаем

  const письмо = собратьПисьмо(данные);
  if (!письмо) return;                   // событие ленте не знакомо

  const кому = Array.isArray(данные.кому) ? данные.кому : [];
  const ктоНомер = Number(данные.ктоНомер) || 0;
  const хозяинНомер = данные.хозяинНомер !== undefined ? Number(данные.хозяинНомер) : 0;
  const код = String(данные.код || '');
  const тип = String(данные.что);
  const отложено = (тип === '2' || тип === '3а' || тип === '3б');
  const задержка = отложено ? ЗАДЕРЖКА_ПОСАДКИ : 0;

  /* Тут только грубый отбор кандидатов (наЭкране/самофильтр/отказы по
     отметке из самого события) — пределы НЕ трогаем: они считаются
     только в момент настоящей отправки, внутри выполнить(), чтобы
     отменённое перепроверкой письмо не съедало лимит как призрак. */
  const получатели = [];
  for (const человек of кому) {
    if (!можноПисать(человек, ктоНомер, хозяинНомер, тип)) continue;
    получатели.push(Number(человек.номер));
  }
  if (получатели.length === 0) return;

  /* Посадка-призрак: вход мог откатиться, пока письмо ждало своих 5 с,
     а адресат — успеть вернуться к экрану. Перепроверки только у
     отложенных писем (2, 3а, 3б): у мгновенных (3в, 4) задержки нет,
     перепроверять «ещё за столом» нечего. Вызвавшего перепроверяем,
     только если у него вообще есть номер (> 0) — без номера событие
     всё равно правдиво, письмо идёт. Падение внутри отложенного дела
     оборачиваем в try/catch — процесс из-за письма ронять нельзя, а
     сбой при проверке ОДНОГО адресата (внутренний try/catch в цикле)
     не должен лишить письма остальных — это чужая беда, не их. */
  const выполнить = function () {
    try {
      if (отложено && ктоНомер > 0 && ещёЗаСтоломВнешний && !ещёЗаСтоломВнешний(код, ктоНомер)) return;
      for (const номер of получатели) {
        try {
          if (отложено && уЭкранаВнешний && уЭкранаВнешний(код, номер)) continue;
          if (отложено && ещёЗаСтоломВнешний && !ещёЗаСтоломВнешний(код, номер)) continue;
          const сейчас = сейчасФункция();
          if (!можноПослать(тип, номер, код, сейчас)) continue;
          послатьТеперь(номер, письмо);
        } catch (беда) {
          /* сбой проверки/отправки этому адресату — молча, остальным письмо всё равно уйдёт */
        }
      }
    } catch (беда) {
      /* сбой вне цикла по адресатам (например, при перепроверке вызвавшего) — молча, процесс жив */
    }
  };

  if (задержка > 0) отложитьФункция(выполнить, задержка);
  else выполнить();
}

/** Забыть память пределов — только для проверок, чтобы начинать с
 *  чистого листа между несвязанными сценариями. */
function забытьВсё() {
  когдаТипу.clear();
  писемЧеловеку.clear();
}

