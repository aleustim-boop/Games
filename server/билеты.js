'use strict';

/* =====================================================================
   Билет на партию с ботом: очки рейтинга за игру, которой сервер не видит.

   Зачем. Рейтинг начисляется в одном месте — в конце партии по сети
   (server/комнаты.js, «учестьИтогПартии»). Партия с ботом идёт целиком
   в браузере, сервер о ней не знает, и очки за неё не доходили ни до
   кого: владелец так и сказал — «мой рейтинг не двигается». За один
   день 10 сентября мимо кассы прошло 219 таких партий.

   ЧТО БИЛЕТ ДАЁТ И ЧЕГО НЕ ДАЁТ — честно. До партии браузер берёт билет:
   сервер записывает, КТО играет (номер из проверенной подписи Telegram),
   во что, против какого бота и когда начал. Уровень бота в билете — это
   слово браузера, но сказанное ДО исхода: подменить его после партии
   («я выиграл, и бот был сложный») уже нельзя, очки считаются по тому,
   что записано в билете. От «партии», которой не было вовсе, билет не
   защищает: скрипт может взять билет, выждать и принести «победу».
   Это известно и принято штабом 10 сентября: сервер партию с ботом
   не видит. Держит такую накрутку только дневной потолок за ботов
   (12 очков — чуть больше одной победы над живым) и замедление ниже.

   Что сервер проверяет и чем замедляет:
     • билет есть, выдан этому же номеру и не использован
       (одна попытка на билет, удачная или нет);
     • партия длилась правдоподобно: дурак — не меньше сорока секунд;
     • билет не просрочен (три часа — с запасом на самую долгую партию);
     • у номера ОДИН живой билет: новый гасит прежние;
     • билет выдаётся номеру не чаще раза в десять секунд;
     • сдача от номера принимается не чаще раза в сорок секунд
       и не больше двадцати раз в сутки;
     • потолок за ботов на сегодня исчерпан — партию не учитываем
       вовсе: ни очков, ни счётчиков партий и побед (они видны всем
       в таблице, и при равных очках выше тот, у кого больше побед).
   Исход («победа», «ничья», «поражение») проверить нечем.

   Стол с несколькими ботами считается как один бот (решение штаба):
   в билете нет числа мест, и так и дешевле, и честнее.

   Всё это живёт в памяти: перезапуск сервера теряет открытые билеты
   (партия, начатая до него, проходит без очков — решение штаба) и
   обнуляет счёт сдач за сутки. Дневной потолок очков при этом цел —
   он хранится в рейтинге на диске.

   Образец такого приёма — server/раздача-дня.js: номер только из подписи,
   наружу — одни числа и слова.
   ===================================================================== */

const crypto = require('crypto');
const рейтинг = require('./рейтинг.js');
/* Уровни ботов — те же слова, что в игре и в таблице цен рейтинга.
   Своей копии списка нет нарочно: правила живут в js/game.js. */
const правила = require('../js/game.js');

/* Для каких игр выдаём билеты и сколько должна длиться партия, чтобы её
   засчитать. Сорок секунд у дурака — это быстрее любой честной партии:
   даже вдвоём раздача, шесть подходов и добор занимают больше.
   Остальных игр здесь пока нет: их длительность ещё не мерили,
   и на просьбу о билете они получают отказ словами. */
const ИГРЫ_С_БИЛЕТАМИ = {
  'дурак': { партияНеКороче: 40 * 1000 }
};

/* Сколько живёт билет. Партия в дурака с ботами — минуты; три часа —
   с большим запасом на свёрнутую игру и забытый телефон. */
const БИЛЕТ_ЖИВЁТ = 3 * 60 * 60 * 1000;

/* Замедление накрутки (см. шапку). Честному игроку оно не мешает:
   партия длится дольше сорока секунд, а двадцать засчитанных партий
   с ботом в день — уже очень много. */
const ВЫДАЧА_НЕ_ЧАЩЕ = 10 * 1000;
const СДАЧА_НЕ_ЧАЩЕ = 40 * 1000;
const СДАЧ_В_СУТКИ = 20;

/* Всего билетов в памяти — от затопления тысячами подписей разом
   (у каждого номера билет один, так что это и потолок номеров). */
const ВСЕГО_НЕ_БОЛЬШЕ = 20000;

/* Какие исходы понимаем — те же слова, что у раздачи дня и рейтинга. */
const ИСХОДЫ = ['победа', 'ничья', 'поражение'];

/* Номер билета: 32 шестнадцатеричных знака (128 случайных битов).
   Угадать чужой нельзя, поэтому перебирать бессмысленно. */
const ВИД_БИЛЕТА = /^[0-9a-f]{32}$/;

const ПОТОЛОК_ИСЧЕРПАН = 'На сегодня очки за ботов кончились — партии с ботом снова засчитаются завтра';

/* Номер билета → { номер, игра, уровень, выдан }. Map помнит порядок
   добавления — самые старые стоят первыми, их и вытесняем. */
const билеты = new Map();

/* Номер игрока → { билет, выдан, сдан, день, сдачЗаДень }: его живой
   билет и когда он в последний раз брал и сдавал. */
const игроки = new Map();

function этоНомерИгрока(номер) {
  return Number.isInteger(номер) && номер > 0;
}

/** «2026-09-11» по местному времени сервера — как день у рейтинга. */
function ключДня(время) {
  const дата = new Date(время);
  return дата.getFullYear() + '-' + String(дата.getMonth() + 1).padStart(2, '0') + '-' +
         String(дата.getDate()).padStart(2, '0');
}

function отказ(причина) {
  return { ок: false, причина: причина };
}

function игрок(номер) {
  if (!игроки.has(номер)) игроки.set(номер, { билет: '', выдан: 0, сдан: 0, день: '', сдачЗаДень: 0 });
  return игроки.get(номер);
}

/** Убрать просроченные билеты. Они стоят по порядку выдачи — идём до первого живого. */
function убратьПросроченные(сейчас) {
  for (const [ключ, запись] of билеты) {
    if (сейчас - запись.выдан <= БИЛЕТ_ЖИВЁТ) break;
    билеты.delete(ключ);
  }
}

/**
 * Выдать билет на партию с ботом.
 * Отвечает { ок: true, билет, партияНеКорочеСекунд } или отказ словами.
 * Номер сюда приходит уже проверенный — из подписи Telegram.
 */
function выдать(номер, игра, уровень, сейчас) {
  const когда = typeof сейчас === 'number' ? сейчас : Date.now();
  if (!этоНомерИгрока(номер)) return отказ('Очки за партии с ботом начисляются только в Telegram');
  const правилаИгры = Object.prototype.hasOwnProperty.call(ИГРЫ_С_БИЛЕТАМИ, игра) ? ИГРЫ_С_БИЛЕТАМИ[игра] : null;
  if (!правилаИгры) return отказ('За партии с ботом в этой игре очки пока не начисляются');
  if (правила.СЛОЖНОСТИ.indexOf(уровень) === -1) return отказ('Такого уровня бота нет');

  const кто = игрок(номер);
  if (кто.выдан && когда - кто.выдан < ВЫДАЧА_НЕ_ЧАЩЕ) {
    return отказ('Билет на партию — не чаще раза в десять секунд');
  }
  убратьПросроченные(когда);
  // Один живой билет на номер: новый гасит прежний.
  if (кто.билет) билеты.delete(кто.билет);
  while (билеты.size >= ВСЕГО_НЕ_БОЛЬШЕ) билеты.delete(билеты.keys().next().value);

  const билет = crypto.randomBytes(16).toString('hex');
  билеты.set(билет, { номер: номер, игра: игра, уровень: уровень, выдан: когда });
  кто.билет = билет;
  кто.выдан = когда;
  return { ок: true, билет: билет, партияНеКорочеСекунд: правилаИгры.партияНеКороче / 1000 };
}

/**
 * Погасить билет: принять исход партии и начислить очки.
 * Отвечает { ок: true, очков, уровень } или отказ словами.
 *
 * Уровень бота — из билета: всё, что браузер пришлёт сверх билета и
 * исхода (уровень, число ботов, очки), сюда даже не доходит.
 */
function погасить(номер, билет, исход, имя, сейчас) {
  const когда = typeof сейчас === 'number' ? сейчас : Date.now();
  if (!этоНомерИгрока(номер)) return отказ('Очки за партии с ботом начисляются только в Telegram');
  if (typeof билет !== 'string' || !ВИД_БИЛЕТА.test(билет)) return отказ('Билета на партию нет');

  const запись = билеты.get(билет);
  if (!запись) return отказ('Билета нет или он уже использован');
  /* Чужой билет не гасим: номер билета знает только его хозяин, и если
     его принёс другой, хозяин всё равно должен суметь сдать свой. */
  if (запись.номер !== номер) return отказ('Билет выдан другому игроку');
  if (ИСХОДЫ.indexOf(исход) === -1) return отказ('Исход партии не понят');

  /* С этого места билет использован при любом ответе: одна попытка
     на билет. Иначе слишком быструю «партию» можно было бы просто
     сдать ещё раз, выждав положенные секунды. */
  билеты.delete(билет);
  const кто = игрок(номер);
  if (кто.билет === билет) кто.билет = '';

  if (когда - запись.выдан > БИЛЕТ_ЖИВЁТ) return отказ('Билет просрочен');
  if (когда - запись.выдан < ИГРЫ_С_БИЛЕТАМИ[запись.игра].партияНеКороче) {
    return отказ('Партия слишком короткая, чтобы её засчитать');
  }
  if (кто.сдан && когда - кто.сдан < СДАЧА_НЕ_ЧАЩЕ) {
    return отказ('Партия с ботом засчитывается не чаще раза в сорок секунд');
  }
  const сегодня = ключДня(когда);
  if (кто.день !== сегодня) {
    кто.день = сегодня;
    кто.сдачЗаДень = 0;
  }
  if (кто.сдачЗаДень >= СДАЧ_В_СУТКИ) {
    return отказ('На сегодня партий с ботом засчитано достаточно — снова завтра');
  }
  /* Потолок за ботов исчерпан — партию не учитываем вовсе: иначе
     партии и победы в таблице росли бы без конца, а они видны всем. */
  if (рейтинг.осталосьОтБотовСегодня(запись.игра, номер) <= 0) return отказ(ПОТОЛОК_ИСЧЕРПАН);

  /* Застолье в том виде, что понимает рейтинг: человек и один бот
     с уровнем из билета. Бота рейтинг не считает (у него нет номера),
     силу игры такая партия не меняет — ботов сила не учитывает. */
  const ничья = исход === 'ничья';
  const застолье = [
    { номер: номер, имя: имя, этоБот: false, парами: false,
      победил: исход === 'победа', ничья: ничья },
    { номер: null, имя: 'Бот', этоБот: true, парами: false, уровень: запись.уровень,
      победил: исход === 'поражение', ничья: ничья }
  ];
  const добавлено = рейтинг.учестьПартию(запись.игра, застолье) || {};
  кто.сдан = когда;
  кто.сдачЗаДень++;
  return { ок: true, очков: добавлено[номер] || 0, уровень: запись.уровень };
}

/** Сколько билетов открыто сейчас — для проверок. */
function сколькоОткрыто() {
  return билеты.size;
}

/** Забыть все билеты и счёт игроков — для проверок. */
function забытьВсё() {
  билеты.clear();
  игроки.clear();
}

module.exports = {
  ИГРЫ_С_БИЛЕТАМИ: ИГРЫ_С_БИЛЕТАМИ,
  БИЛЕТ_ЖИВЁТ: БИЛЕТ_ЖИВЁТ,
  ВЫДАЧА_НЕ_ЧАЩЕ: ВЫДАЧА_НЕ_ЧАЩЕ,
  СДАЧА_НЕ_ЧАЩЕ: СДАЧА_НЕ_ЧАЩЕ,
  СДАЧ_В_СУТКИ: СДАЧ_В_СУТКИ,
  ПОТОЛОК_ИСЧЕРПАН: ПОТОЛОК_ИСЧЕРПАН,
  ИСХОДЫ: ИСХОДЫ,
  выдать: выдать,
  погасить: погасить,
  сколькоОткрыто: сколькоОткрыто,
  забытьВсё: забытьВсё
};
