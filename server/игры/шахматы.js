/* =====================================================================
   ШАХМАТЫ ДЛЯ СЕРВЕРА — доска на двоих по сети.

   Своих правил здесь нет ни строчки: ходы, шах, мат, рокировка, взятие
   на проходе, превращение и ничьи берутся из js/шахматы-правила.js —
   того же файла, что читает браузер. Правила не раздваиваются: иначе
   сервер и экран однажды разойдутся в решениях.

   Устройство повторяет server/игры/шашки.js: перевод с языка комнаты
   («место», «ход игрока», «вид для игрока») на язык шахмат и обратно.
   Договор игры с комнатой описан в server/игры/реестр.js.

   КЛИЕНТУ НЕ ВЕРИМ. Вид собирается вручную, поле за полем (видДляИгрока).
   Позицию отдаём строкой FEN: только в ней есть права на рокировку, поле
   взятия на проходе и счётчики. Картинка доски без FEN теряет всё это,
   и экран, собравший позицию из картинки, запретил бы законную рокировку.

   ЦВЕТА. Первая партия — белые достаются случайно. В реванше цвета
   меняются: кто играл чёрными, садится белыми (см. следующийНачинающий).

   ЧАСЫ. Контроль времени по Фишеру (см. раздел «Часы» ниже): выбирается
   полем настроек стола «контрольШахмат», время ведёт только сервер.

   ЗНАКИ ВНИМАНИЯ. Общий набор дурака (js/деберц-знаки.js), как у нард:
   наружу уходят только допустимые номера, поле за полем.
   ===================================================================== */

const Правила = require('../../js/шахматы-правила.js');
const Бот = require('../../js/шахматы-бот.js');
/* Знаки внимания — общий набор дурака, тот же, что у нард и домино. */
const Знаки = require('../../js/деберц-знаки.js');
const { номерМеста } = require('../партия-по-сети.js');

/* За доской ровно двое. */
const МЕСТ_ЗА_ДОСКОЙ = 2;

/* Пауза перед ходом бота — чтобы человек успел заметить свой ход. */
const ПАУЗА_БОТА = 700;

/* Сколько бот думает НА СЕРВЕРЕ. Счёт синхронный: пока он идёт, стоят
   все остальные столы. Поэтому бюджет меньше браузерного — тот же,
   что у шашек. */
const БЮДЖЕТ_НА_СЕРВЕРЕ = 150;

/* После отказа от ничьей — не раньше чем через шесть полуходов, как у
   шашек: повторными просьбами удобно мешать сопернику думать. */
const ЖДАТЬ_ПОСЛЕ_ОТКАЗА = 6;

/* Пауза перед автоответом бота на предложение ничьей — короче паузы
   перед обычным ходом: отвечать тут нечего обдумывать, а долгое «ждём
   ответа» и есть та проблема, которую отвечает решать эта пауза. */
const ПАУЗА_БОТА_НА_ОТВЕТ_НИЧЬЕЙ = 400;

/* ---------------------------------------------------------------------
   ЧАСЫ (схема Фишера): у каждого свой запас, идут часы только того, чей
   ход; после своего хода игрок получает «добавку». Числа — те же, что у
   игры с ботом в js/шахматы-экран.js (НАСТРОЙКИ_КОНТРОЛЯ), только здесь
   в миллисекундах. Белый список: чужое слово из настроек = «без часов».
   --------------------------------------------------------------------- */
const КОНТРОЛИ = {
  'блиц': { старт: 5 * 60 * 1000, добавка: 3 * 1000 },
  'рапид': { старт: 10 * 60 * 1000, добавка: 0 },
  'классика': { старт: 30 * 60 * 1000, добавка: 0 }
};

/* Будильник комнаты может сработать на миллисекунду раньше срока. Без
   допуска ходПоПросрочке ответил бы «ещё не пора», а второго будильника
   комната уже не заведёт — часы встали бы на нуле навсегда. */
const ДОПУСК_ПРОСРОЧКИ_МС = 50;

/* Единственный источник времени для часов. Проверка подменяет его через
   module.exports.сейчас, чтобы двигать время без ожидания. */
function сейчас() {
  return module.exports.сейчас();
}

/** Выбранный контроль или null («нет» и всё незнакомое). */
function контрольИзНастроек(настройки) {
  const слово = настройки ? настройки.контрольШахмат : undefined;
  if (typeof слово !== 'string') return null;
  if (!Object.prototype.hasOwnProperty.call(КОНТРОЛИ, слово)) return null;
  return слово;
}

/** Завести часы новой партии: у обоих полный запас, идут часы белых. */
function завестиЧасы(контроль) {
  const настройка = КОНТРОЛИ[контроль];
  return {
    контроль: контроль,
    белые: настройка.старт,
    чёрные: настройка.старт,
    добавка: настройка.добавка,
    с_какого_момента: сейчас(),
    стоят: false
  };
}

/** Остаток цвета в мс на эту минуту — у ходящего вычитаем идущее время. */
function остатокЦвета(партия, цвет) {
  const часы = партия.часы;
  const запас = цвет === Правила.БЕЛЫЕ ? часы.белые : часы.чёрные;
  /* «завершена» проверяем отдельно от «стоят»: комната умеет закрыть
     партию сама (отмена при уходе), мимо записатьИтог, — часы тогда
     не остановлены, но идти им уже незачем. */
  if (часы.стоят || партия.завершена || Правила.чейХод(партия.позиция) !== цвет) return запас;
  return Math.max(0, запас - (сейчас() - часы.с_какого_момента));
}

/** Списать с цвета время, прошедшее с начала его хода, и перезапустить отсчёт. */
function списатьПрошедшее(партия, цвет) {
  const часы = партия.часы;
  const остаток = остатокЦвета(партия, цвет);
  if (цвет === Правила.БЕЛЫЕ) часы.белые = остаток;
  else часы.чёрные = остаток;
  часы.с_какого_момента = сейчас();
}

/** Остановить часы в конце партии: ходящий честно платит за последний ход. */
function остановитьЧасы(партия) {
  if (!партия.часы || партия.часы.стоят) return;
  списатьПрошедшее(партия, Правила.чейХод(партия.позиция));
  партия.часы.стоят = true;
}

/** Для будильника комнаты: сколько СЕКУНД осталось ходящему. */
function остатокВремениНаХод(партия) {
  if (!партия || партия.завершена || !партия.часы || партия.часы.стоят) return Infinity;
  return остатокЦвета(партия, Правила.чейХод(партия.позиция)) / 1000;
}

/**
 * Время вышло: проигрывает тот, у кого упал флаг. Исключение — у соперника
 * один голый король: поставить мат ему нечем, это ничья (то же правило,
 * что у игры с ботом, объявитьВремяВышло в js/шахматы-экран.js).
 */
function ходПоПросрочке(партия) {
  if (!партия || партия.завершена || !партия.часы) return null;
  const цвет = Правила.чейХод(партия.позиция);
  if (остатокЦвета(партия, цвет) > ДОПУСК_ПРОСРОЧКИ_МС) return null;

  const кто = местоЦвета(партия, цвет);
  if (цвет === Правила.БЕЛЫЕ) партия.часы.белые = 0;
  else партия.часы.чёрные = 0;
  партия.часы.с_какого_момента = сейчас();
  партия.часы.стоят = true;
  партия.ничьяПредложена = null;

  const победитель = цвет === Правила.БЕЛЫЕ ? Правила.ЧЁРНЫЕ : Правила.БЕЛЫЕ;
  const толькоКороль = Правила.сколькоФигур(партия.позиция, победитель).всего === 1;
  if (толькоКороль) {
    Правила.завершитьСПричиной(партия.позиция, 'ничья',
      'время вышло, а мата поставить нечем — на доске один король');
  } else {
    Правила.завершитьСПричиной(партия.позиция, победитель, 'время вышло');
  }
  записатьИтог(партия);
  return { ктоСделал: кто };
}

/**
 * Раздать — расставить фигуры и назначить цвета.
 *
 * Комната смотрит в партию четырьмя полями: «игроки», «завершена»,
 * «результат», «проигравшие». Позицию и цвета читает только этот файл.
 */
function раздать(ктоНачинает, настройки) {
  const все = (настройки && Array.isArray(настройки.игроки) ? настройки.игроки : [])
    .slice(0, МЕСТ_ЗА_ДОСКОЙ);
  /* Белые — тот, кого назвали начинающим (в реванше это игравший
     чёрными). Не назвали — жребий: у хозяина стола не должно быть
     вечного преимущества первого хода. */
  /* Жребий — не правило шахмат, а случайность: Math.random предсказуем
     (по паре чисел его состояние восстанавливается), поэтому берём у
     node:crypto — так же, как в нардах. */
  const белые = все.indexOf(ктоНачинает) !== -1
    ? ктоНачинает
    : все[require('node:crypto').randomInt(все.length)];
  const чёрные = все.filter(function (место) { return место !== белые; })[0] || null;

  const цвета = {};
  if (белые) цвета[белые] = Правила.БЕЛЫЕ;
  if (чёрные) цвета[чёрные] = Правила.ЧЁРНЫЕ;

  const партия = {
    игроки: все,
    завершена: false,
    результат: null,
    проигравшие: [],
    цвета: цвета,
    позиция: Правила.создатьПартию(),
    последнийХод: null
  };
  /* Без контроля поля «часы» нет вовсе — по нему и вид, и будильник
     комнаты понимают, что партия без времени. */
  const контроль = контрольИзНастроек(настройки);
  if (контроль) партия.часы = завестиЧасы(контроль);
  return партия;
}

/**
 * Кто начинает следующую партию за этим столом. Комната спрашивает это
 * перед каждой раздачей: в реванше белыми садится тот, кто играл
 * чёрными. Прошлой партии нет — решает жребий в раздать.
 */
function следующийНачинающий(прошлая) {
  if (!прошлая || !прошлая.цвета) return null;
  return местоЦвета(прошлая, Правила.ЧЁРНЫЕ);
}

/** Место, которое играет этим цветом. */
function местоЦвета(партия, цвет) {
  for (const место of партия.игроки) {
    if (партия.цвета[место] === цвет) return место;
  }
  return null;
}

/** Чей сейчас ход — место или null, если партия кончилась. */
function чейХод(партия) {
  if (!партия || партия.завершена) return null;
  return местоЦвета(партия, Правила.чейХод(партия.позиция));
}

/**
 * Перенести итог из правил в поля партии, которые читает комната.
 * Мат, пат, повторение, 50 ходов, «нечем матовать» — решают правила.
 */
function записатьИтог(партия) {
  const итог = Правила.итог(партия.позиция);
  if (!итог) return;
  остановитьЧасы(партия);
  партия.завершена = true;
  if (итог.ничья) {
    партия.результат = null;
    партия.проигравшие = [];
    партия.ничья = true;
    партия.причинаКонца = итог.причина;
    return;
  }
  const победитель = местоЦвета(партия, итог.победитель);
  партия.результат = победитель;
  партия.проигравшие = партия.игроки.filter(function (место) { return место !== победитель; });
  партия.ничья = false;
  партия.причинаКонца = итог.причина;
}

/**
 * Ход игрока: { действие: 'ход', откуда, куда, превращение? }.
 * Ничья по соглашению и сдача приходят той же дверью.
 */
function сделатьХод(партия, ктоЯ, намерение) {
  if (!партия || партия.завершена) {
    return { принято: false, причина: 'Партия уже закончена' };
  }
  const действие = намерение && typeof намерение.действие === 'string'
    ? намерение.действие : '';
  if (действие === 'ничья') return предложитьНичью(партия, ктоЯ);
  if (действие === 'ничья-да') return ответитьНаНичью(партия, ктоЯ, true);
  if (действие === 'ничья-нет') return ответитьНаНичью(партия, ктоЯ, false);
  if (действие === 'сдаться') return сдаться(партия, ктоЯ);

  if (действие !== 'ход') {
    return { принято: false, причина: 'В шахматах так не ходят' };
  }
  if (чейХод(партия) !== ктоЯ) {
    return { принято: false, причина: 'Сейчас не ваш ход' };
  }
  /* Флаг уже упал, а будильник комнаты ещё не успел сработать: ход
     опоздал. Итог объявит сам будильник (ходПоПросрочке) — он вот-вот. */
  const цветХодящего = Правила.чейХод(партия.позиция);
  if (партия.часы && остатокЦвета(партия, цветХодящего) <= 0) {
    return { принято: false, причина: 'Время вышло — ход не успел' };
  }

  const выбор = найтиЗаконныйХод(партия, намерение);
  if (выбор.причина) return { принято: false, причина: выбор.причина };
  const ход = выбор.ход;

  /* Запись («Nf3», «O-O», «e8=Q+») считается ДО хода: правилам нужна
     позиция, в которой ход ещё не сделан. */
  const запись = Правила.запись(партия.позиция, ход);
  /* Остаток считаем ДО хода: после него часы «идут» уже у соперника. */
  const остатокДоХода = партия.часы ? остатокЦвета(партия, цветХодящего) : 0;
  if (!Правила.сделатьХод(партия.позиция, ход)) {
    return { принято: false, причина: 'Этот ход не получился — попробуйте другой' };
  }
  /* Фишер: с ходившего списываем потраченное и сразу даём добавку.
     Цвет запомнен ДО хода — после него правила говорят уже о сопернике. */
  if (партия.часы) {
    const часы = партия.часы;
    const сДобавкой = остатокДоХода + часы.добавка;
    if (цветХодящего === Правила.БЕЛЫЕ) часы.белые = сДобавкой;
    else часы.чёрные = сДобавкой;
    часы.с_какого_момента = сейчас();
  }

  /* Ход снимает предложение ничьей, только если сходил НЕ тот, кто его
     сделал: это его молчаливый отказ, тот же отказ, что явным «нет», —
     с той же паузой перед следующей просьбой. Ход самого предложившего
     предложение не трогает: он мог сходить, ещё ожидая ответа соперника
     (это допускает почемуНельзяПредлагать — предлагать можно в любой
     момент, не только на своём ходу), и его собственный ход — это не
     ответ, а просто ход. */
  if (партия.ничьяПредложена && партия.ничьяПредложена.кто !== ктоЯ) {
    партия.ничьяОтказ = { кому: партия.ничьяПредложена.кто, наПолуходе: сколькоПолуходов(партия) };
    партия.ничьяПредложена = null;
  }
  партия.последнийХод = {
    откуда: ход.откуда,
    куда: ход.куда,
    запись: запись,
    чей: ктоЯ
  };
  записатьИтог(партия);

  return { принято: true, событие: ход.взятие ? 'взятие' : 'ход' };
}

/**
 * Найти законный ход по присланным полям. Берём у присланного только
 * «откуда», «куда» и «превращение» и только строками; сам ход — всегда
 * из списка законных ходов правил.
 *
 * Превращение: фигуру выбирает игрок, и выбрать её можно только из тех,
 * что правила предлагают для этого хода (ферзь, ладья, слон, конь).
 * Не выбрал — отказ: подставлять ферзя за человека нельзя, иногда
 * нужен именно конь.
 */
function найтиЗаконныйХод(партия, намерение) {
  const откуда = typeof намерение.откуда === 'string' ? намерение.откуда.toLowerCase() : '';
  const куда = typeof намерение.куда === 'string' ? намерение.куда.toLowerCase() : '';
  const годные = Правила.возможныеХоды(партия.позиция).filter(function (х) {
    return х.откуда === откуда && х.куда === куда;
  });
  if (годные.length === 0) return { причина: почемуНельзя(партия, откуда, куда) };

  const превращения = годные
    .map(function (х) { return х.превращение; })
    .filter(function (фигура) { return typeof фигура === 'string'; });
  const просят = намерение.превращение;

  if (превращения.length === 0) {
    if (просят !== undefined && просят !== null) {
      return { причина: 'Здесь пешка не превращается — фигуру выбирать не нужно' };
    }
    return { ход: годные[0] };
  }
  if (typeof просят !== 'string' || превращения.indexOf(просят) === -1) {
    return { причина: 'Пешка дошла до края — выберите фигуру: ферзь, ладья, слон или конь' };
  }
  return { ход: годные[превращения.indexOf(просят)] };
}

/** Почему ход не подошёл — словами, понятными игроку. */
function почемуНельзя(партия, откуда, куда) {
  const фигура = откуда ? Правила.фигура(партия.позиция, откуда) : null;
  const ходит = Правила.чейХод(партия.позиция);
  if (!фигура || фигура.цвет !== ходит) return 'На этом поле нет вашей фигуры';
  const шах = Правила.подШахом(партия.позиция);
  const естьХоды = Правила.ходыФигуры(партия.позиция, откуда).length > 0;
  if (!естьХоды) {
    return шах ? 'Вам шах — эта фигура от него не спасает' : 'Этой фигуре сейчас некуда пойти';
  }
  if (шах) return 'Вам шах — такой ход его не снимает';
  return 'Так ' + (куда ? 'эта фигура не ходит' : 'не ходят — укажите поле');
}

/* ---------------------------------------------------------------------
   НИЧЬЯ ПО СОГЛАШЕНИЮ — перенос шашечной: предложение живёт внутри
   партии, частота — по полуходам, после отказа ждать шесть полуходов
   должен тот, кому отказали.
   --------------------------------------------------------------------- */

function сколькоПолуходов(партия) {
  return партия && партия.позиция ? Number(партия.позиция.полуходов) || 0 : 0;
}

function почемуНельзяПредлагать(партия, ктоЯ) {
  if (партия.завершена) return 'Партия уже закончена';
  if (партия.игроки.indexOf(ктоЯ) === -1) return 'Вас нет за этой доской';
  if (партия.ничьяПредложена) {
    return партия.ничьяПредложена.кто === ктоЯ
      ? 'Вы уже предложили ничью — ждём ответа'
      : 'Соперник сам предложил ничью — ответьте на его предложение';
  }
  const отказ = партия.ничьяОтказ;
  if (отказ && отказ.кому === ктоЯ) {
    const прошло = сколькоПолуходов(партия) - отказ.наПолуходе;
    if (прошло < ЖДАТЬ_ПОСЛЕ_ОТКАЗА) {
      const осталось = Math.ceil((ЖДАТЬ_ПОСЛЕ_ОТКАЗА - прошло) / 2);
      return 'Соперник только что отказался. Предложить снова можно через ' +
             осталось + (осталось === 1 ? ' ход' : ' хода');
    }
  }
  return '';
}

function предложитьНичью(партия, ктоЯ) {
  const нельзя = почемуНельзяПредлагать(партия, ктоЯ);
  if (нельзя) return { принято: false, причина: нельзя };
  партия.ничьяПредложена = { кто: ктоЯ, наПолуходе: сколькоПолуходов(партия) };
  return { принято: true, событие: 'ничья-предложена' };
}

/**
 * Ответ на предложение. Согласие закрывает партию через правила
 * (завершитьСПричиной) — ничья одна и та же и для рейтинга, и для экрана.
 */
function ответитьНаНичью(партия, ктоЯ, согласен) {
  /* Та же проверка, что и при предложении (почемуНельзяПредлагать): отвечать
     на ничью может только тот, кто сидит за этой доской, иначе случайный
     зритель мог бы решить исход чужой партии. */
  if (партия.игроки.indexOf(ктоЯ) === -1) {
    return { принято: false, причина: 'Вас нет за этой доской' };
  }
  const предложение = партия.ничьяПредложена;
  if (!предложение) return { принято: false, причина: 'Ничью никто не предлагал' };
  if (предложение.кто === ктоЯ) {
    return { принято: false, причина: 'Это ваше предложение — ответить может соперник' };
  }
  партия.ничьяПредложена = null;

  if (!согласен) {
    партия.ничьяОтказ = { кому: предложение.кто, наПолуходе: сколькоПолуходов(партия) };
    return { принято: true, событие: 'ничья-отклонена' };
  }

  Правила.завершитьСПричиной(партия.позиция, 'ничья', 'по соглашению');
  записатьИтог(партия);
  return { принято: true, событие: 'ничья-согласие' };
}

/**
 * Сдаться. Сдаётся тот, кто нажал кнопку, а не тот, чей ход: по сети
 * это разные люди. Поэтому цвет берём из партия.цвета[ктоЯ].
 */
function сдаться(партия, ктоЯ) {
  if (!партия || партия.завершена) {
    return { принято: false, причина: 'Партия уже закончена' };
  }
  const мойЦвет = партия.цвета[ктоЯ];
  if (!мойЦвет) return { принято: false, причина: 'Вас нет за этой доской' };

  const цветПротивника = мойЦвет === Правила.БЕЛЫЕ ? Правила.ЧЁРНЫЕ : Правила.БЕЛЫЕ;
  партия.ничьяПредложена = null;
  Правила.завершитьСПричиной(партия.позиция, цветПротивника,
    (мойЦвет === Правила.БЕЛЫЕ ? 'белые' : 'чёрные') + ' сдались');
  записатьИтог(партия);
  return { принято: true, событие: 'сдался' };
}

/**
 * Ждёт ли это место ответа на чужое предложение ничьей. Своего собственного
 * предложения место не «ждёт» — отвечать самому себе нельзя.
 */
function естьЧегоЖдатьНичьей(партия, место) {
  const предложение = партия && !партия.завершена ? партия.ничьяПредложена : null;
  return Boolean(предложение) && предложение.кто !== место;
}

/**
 * Бот сразу отвечает «нет» на чужое предложение ничьей — не дожидаясь
 * своей очереди хода по доске. Без этого человек видел бы вечное «ждём
 * ответа»: у бота нет своего хода, пока ходит человек, а обычная очередь
 * дойдёт до бота, только когда он сам сделает ход и передаст её дальше.
 */
function ботОтвечаетНичьюНет(партия, место) {
  const ответ = ответитьНаНичью(партия, место, false);
  if (!ответ.принято) return null;
  return { событие: ответ.событие, ктоСделал: место, эмоция: null, бросок: null };
}

/**
 * Ход за бота — настоящим ботом js/шахматы-бот.js и через ту же дверь
 * «сделатьХод», что у человека: законность проверяется одинаково.
 * Знаков бот не подаёт: голоса у шахматного бота нет.
 *
 * Сюда зовут, когда очередь хода и так дошла до бота (обычным темпом
 * бота): предложение ничьей проверяем первым, чтобы бот не сходил молча
 * мимо вопроса, а сперва ответил на него.
 */
function ходЗаБота(партия, место, уровень) {
  if (!партия || партия.завершена) return null;
  if (естьЧегоЖдатьНичьей(партия, место)) return ботОтвечаетНичьюНет(партия, место);
  if (чейХод(партия) !== место) return null;

  const выбранный = Бот.выбратьХодСразу(партия.позиция, {
    уровень: уровень || Бот.УРОВЕНЬ_ПО_УМОЛЧАНИЮ,
    бюджетМс: БЮДЖЕТ_НА_СЕРВЕРЕ
  });
  if (!выбранный) return null;

  const ответ = сделатьХод(партия, место, {
    действие: 'ход',
    откуда: выбранный.откуда,
    куда: выбранный.куда,
    превращение: выбранный.превращение
  });
  if (!ответ.принято) return null;
  return { событие: ответ.событие, ктоСделал: место, эмоция: null, бросок: null };
}

/**
 * Ход вне очереди: бот отвечает на предложение ничьей, даже когда очередь
 * по доске сейчас не его. Без этой двери ответ ждал бы, пока предложивший
 * человек сам не сходит и очередь по правилам не дойдёт до бота, — а это
 * и есть то самое зависание «ждём ответа», которое видит игрок.
 */
function ктоИзБотовОтветитНаНичью(партия, уровеньБота) {
  if (!партия || партия.завершена || !партия.ничьяПредложена) return null;
  const уровень = typeof уровеньБота === 'function' ? уровеньБота : function () { return null; };
  for (const место of партия.игроки) {
    if (!естьЧегоЖдатьНичьей(партия, место)) continue;
    if (!уровень(место)) continue;   // это человек — молчим, ждём его собственного ответа
    return { кто: место };
  }
  return null;
}

/**
 * Что видит этот игрок. Собираем вручную, поле за полем; из добавки
 * комнаты тоже берём по одному полю — сырые полуфабрикаты (внутренние
 * имена мест, сырое событие) наружу не уходят.
 */
/**
 * Знак внимания глазами этого игрока. Из сырого знака комнаты берём
 * только разрешённое: внутренние имена мест наружу не уходят. «от» и
 * «кому» — места относительно смотрящего: 0 — я, 1 — соперник (за доской
 * двое); по ним панель знаков решает, откуда и куда летит бросок.
 */
function знакДляИгрока(сырое, ктоЯ) {
  if (!сырое || !Знаки.этоЗнак(сырое.номер)) return null;
  const знак = {
    номер: сырое.номер,
    порядковый: Number(сырое.порядковый) || 0,
    имя: сырое.имя ? String(сырое.имя) : '',
    этоЯ: сырое.кто === ктоЯ,
    от: сырое.кто === ктоЯ ? 0 : 1,
    кому: null
  };
  if (сырое.цель) {
    знак.цель = сырое.имяЦели ? String(сырое.имяЦели) : '';
    знак.вМеня = сырое.цель === ктоЯ;
    знак.кому = сырое.цель === ктоЯ ? 0 : 1;
  }
  return знак;
}

function видДляИгрока(партия, ктоЯ, добавка) {
  const пришло = добавка || {};
  const места = Array.isArray(пришло.места) ? пришло.места : [];

  /* Стол на двоих или компания с прихожей — по тому, прислала ли комната
     список мест. Тот же приём, что у шашек (server/игры/шашки.js): за
     доской в шахматах всегда двое, а вот СТОЛ бывает разный — обычная
     игра вдвоём (список не шлют вовсе) и стол-компания «компанией: true»
     (список есть, даже когда за столом всего двое). Пустой массив в виде
     игра на телефоне приняла бы за признак компании (урок шашек 29.09:
     хозяин читал слова гостя про самого себя), поэтому у стола на двоих
     поля «застолом» не будет совсем, а не пустого списка. */
  const этоКомпания = места.length > 0;

  const вид = {
    игра: 'шахматы',
    код: пришло.код,
    этап: пришло.этап,
    версия: пришло.версия,
    номерСобытия: пришло.номерСобытия,
    событие: пришло.событие || '',
    /* Короткое слово события из закрытого набора — экран решает по нему,
       а не по тексту для человека. */
    видСобытия: пришло.событиеСырое && typeof пришло.событиеСырое.что === 'string'
      ? пришло.событиеСырое.что : '',
    имяСобытия: пришло.событиеСырое && пришло.событиеСырое.имя
      ? String(пришло.событиеСырое.имя) : '',
    сыграноПартий: пришло.сыграноПартий,
    открытыйСтол: пришло.открытыйСтол === true,
    яХочуЕщё: пришло.яХочуЕщё === true,
    соперникХочетЕщё: пришло.соперникХочетЕщё === true,
    соперникПришёл: пришло.соперникПришёл === true,
    соперникНаСвязи: пришло.соперникНаСвязи === true,
    соперникУшёл: пришло.соперникУшёл === true,
    мест: пришло.мест,
    мойНомер: пришло.мойНомер,
    /* По этим признакам мост решает, показывать ли кнопку «Сказать». */
    знакиВниманияЕсть: Знаки.сколько() > 0,
    броскиЕсть: Знаки.БРОСКИ.length > 0,
    застолом: места.map(function (место) {
      return {
        номер: номерМеста(место.ключ),
        имя: место.имя,
        этоЯ: место.ключ === ктоЯ,
        этоБот: место.этоБот === true,
        хозяин: место.хозяин === true,
        наСвязи: место.наСвязи !== false,
        ушёл: место.ушёл === true,
        хочетЕщё: место.хочетЕщё === true,
        /* Цвет — единственное, что шахматы добавляют к общей плашке места.
           Пока не раздали, цвета ещё нет: он назначается при раздаче. */
        цвет: партия && партия.цвета ? (партия.цвета[место.ключ] || null) : null
      };
    })
  };

  /* Поля стола-компании кладём отдельно и только для неё: их наличие
     и есть признак, по которому игра на телефоне решает, показывать ли
     прихожую со списком мест и кнопку «Начать игру». */
  if (этоКомпания) {
    вид.яХозяин = пришло.яХозяин === true;
    вид.можноНачать = пришло.можноНачать === true;
  } else {
    /* Списка мест у стола на двоих быть не должно ВОВСЕ — даже пустого.
       Пустой массив это тоже массив, и игра на телефоне принимает его
       за признак компании (урок шашек). */
    delete вид.застолом;
  }

  /* Свежий знак внимания. Знак может прийти и в прихожей, до раздачи,
     поэтому кладём его раньше выхода «партии ещё нет». */
  const знак = знакДляИгрока(пришло.знакСырой, ктоЯ);
  if (знак) вид.знакВнимания = знак;

  if (!партия) return вид;

  const предложение = партия.завершена ? null : партия.ничьяПредложена;
  if (предложение) {
    вид.предложениеНичьей = {
      моё: предложение.кто === ктоЯ,
      ждётМеня: предложение.кто !== ктоЯ
    };
  }
  вид.можноПредложитьНичью = почемуНельзяПредлагать(партия, ктоЯ) === '';

  const соперникЗаДоской = партия.игроки.filter(function (кто) { return кто !== ктоЯ; })[0];
  if (соперникЗаДоской) вид.креслоСоперника = партия.игроки.indexOf(соперникЗаДоской) + 1;

  вид.fen = Правила.fenПартии(партия.позиция);
  вид.доска = Правила.картинкаПартии(партия.позиция);
  вид.чейХод = партия.завершена ? null : Правила.чейХод(партия.позиция);
  вид.мойЦвет = партия.цвета[ктоЯ] || null;
  вид.яХожу = чейХод(партия) === ктоЯ;
  вид.шах = партия.завершена ? false : Правила.подШахом(партия.позиция);
  вид.завершена = партия.завершена === true;

  /* Часы: остаток каждого на момент сборки вида, чьи идут и время
     сервера — по нему экран досчитывает секунды до следующего вида. */
  if (партия.часы) {
    const стоят = партия.завершена || партия.часы.стоят;
    const ходит = Правила.чейХод(партия.позиция);
    вид.часы = {
      /* Слово контроля — для подзаголовка «Блиц • 5 + 3» у обоих игроков;
         только из белого списка, чужое слово не уходит. */
      контроль: Object.prototype.hasOwnProperty.call(КОНТРОЛИ, партия.часы.контроль) ? партия.часы.контроль : null,
      белые: Math.round(остатокЦвета(партия, Правила.БЕЛЫЕ)),
      чёрные: Math.round(остатокЦвета(партия, Правила.ЧЁРНЫЕ)),
      идут: стоят ? null : (ходит === Правила.БЕЛЫЕ ? 'w' : 'b'),
      сервер: сейчас()
    };
  }

  if (партия.последнийХод) {
    вид.последнийХод = {
      откуда: партия.последнийХод.откуда,
      куда: партия.последнийХод.куда,
      запись: партия.последнийХод.запись,
      /* Чей ход — цветом: внутренних имён мест у экрана нет. */
      чей: партия.цвета[партия.последнийХод.чей] || null,
      мой: партия.последнийХод.чей === ктоЯ
    };
  }

  if (партия.завершена) {
    вид.итог = {
      победитель: партия.результат ? партия.цвета[партия.результат] || null : null,
      ничья: партия.ничья === true,
      причина: партия.причинаКонца || null,
      яВыиграл: Boolean(партия.результат) && партия.результат === ктоЯ
    };
  }

  return вид;
}

/**
 * Рассказ о событии словами. Ни одного глагола прошедшего времени про
 * соперника: рода по имени не узнать, а «Аня сходил» читается как
 * неряшливость игры.
 */
function текстСобытия(событие, ктоЯ) {
  if (!событие || !событие.что) return '';
  const своё = событие.кто === ктоЯ;
  const имя = своё ? 'Вы' : (событие.имя || 'Соперник');

  if (событие.что === 'ход') return имя + ': ход';
  if (событие.что === 'взятие') return имя + ': взятие';
  if (событие.что === 'ничья-предложена') return имя + ' предлагает ничью';
  if (событие.что === 'ничья-отклонена') {
    return своё ? 'Вы играете дальше' : 'Соперник хочет играть дальше';
  }
  if (событие.что === 'ничья-согласие') return 'Ничья по соглашению';
  if (событие.что === 'сдался') return своё ? 'Вы сдались' : 'Соперник сдаётся';
  if (событие.что === 'ход-по-времени') {
    return своё ? 'У вас кончилось время' : 'У соперника кончилось время';
  }
  if (событие.что === 'вошёл') return имя + ' за доской';
  if (событие.что === 'ушёл' || событие.что === 'ушёл-из-комнаты') {
    return имя + ' больше не играет';
  }
  if (событие.что === 'пропал' || событие.что === 'пропал-бот') {
    return имя + ' слишком долго не на связи — партия закончена';
  }
  return '';
}

