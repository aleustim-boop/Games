/* Обычная Error из правил (throw Error('текст')) уже написана по-русски —
   показываем как есть. Техническую ошибку JS (TypeError, RangeError,
   ReferenceError, SyntaxError, а то и не Error вовсе) игрок видеть не
   должен, даже если в её тексте случайно есть русские буквы (утечка вида
   «Cannot read properties of undefined (reading 'флоты')»). Такую ошибку —
   со стеком — пишем в журнал сервера; обычный отказ правил в журнал не
   пишем, иначе он забьётся частыми отказами и потеряется настоящий сбой. */
function понятнаяПричина(e, где) {
  if (e instanceof Error && e.constructor === Error) return e.message;
  console.error(где + ": сбой хода", e);
  return "Такой ход не принят";
}
function раздать(_, settings = {}) {
  const игроки = (settings.игроки || []).slice();
  if (
    игроки.length < 2 ||
    игроки.length > 6 ||
    new Set(игроки).size !== игроки.length
  )
    throw Error("Нужно 2–6 участников");
  return {
    игроки,
    игра: P.create(игроки.length, undefined, true),
    завершена: false,
    результат: null,
    проигравшие: [],
  };
}
function чейХод(p) {
  return !p || p.завершена ? null : p.игроки[P.who(p.игра)] || null;
}
function сделатьХод(p, key, a = {}) {
  const i = p?.игроки.indexOf(key);
  if (!p || i < 0 || p.завершена)
    return { принято: false, причина: "Партия недоступна" };
  try {
    if (!a || typeof a !== "object") throw Error("Ход не разобран");
    if (!["монополия", "сдаться"].includes(a.действие))
      throw Error("Неизвестное действие");
    if (
      a.действие === "монополия" &&
      (!a.move || typeof a.move !== "object" || typeof a.move.type !== "string")
    )
      throw Error("Не хватает данных хода");
    P.action(
      p.игра,
      i,
      a.действие === "сдаться" ? { type: "surrender" } : a.move,
    );
    if (p.игра.phase === "finished") {
      p.завершена = true;
      p.результат = p.игроки[p.игра.winner];
      p.проигравшие = p.игроки.filter((k) => k !== p.результат);
    }
    return { принято: true, событие: a.move?.type || a.действие };
  } catch (e) {
    return { принято: false, причина: понятнаяПричина(e, "монополия") };
  }
}
function ходЗаБота(p, key) {
  const i = p.игроки.indexOf(key);
  if (i < 0 || p.завершена) return null;
  const move = B.move(P.view(p.игра, i));
  return move && сделатьХод(p, key, { действие: "монополия", move }).принято
    ? { событие: move.type, ктоСделал: key }
    : null;
}
function видДляИгрока(p, key, d = {}) {
  const v = {
    игра: "монополия",
    код: d.код,
    этап: d.этап,
    версия: d.версия,
    номерСобытия: d.номерСобытия,
    событие: d.событие || "",
    сыграноПартий: d.сыграноПартий,
    яХочуЕщё: !!d.яХочуЕщё,
    соперникХочетЕщё: !!d.соперникХочетЕщё,
    соперникПришёл: !!d.соперникПришёл,
    соперникНаСвязи: !!d.соперникНаСвязи,
    соперникУшёл: !!d.соперникУшёл,
    имяСоперника: String(d.имяСоперника || "Соперник"),
    завершена: !!p?.завершена,
    /* Стол закончил партию по согласию — экран по этому признаку пишет
       «Партия закончена по согласию». Признак «прервана» внутри вида общий
       (согласие и отмена без итога), по нему так писать нельзя. Поле есть
       всегда, как у общего вида (server/партия-по-сети.js): без согласия — false. */
    поСогласию: p?.законченаПоСогласию === true,
    яХожу: чейХод(p) === key,
    /* Знаки внимания — общий набор дурака (общее/js/деберц-знаки.js). По этим
       признакам экран решает, показывать ли панель «Сказать». */
    знакиВниманияЕсть: Знаки.сколько() > 0,
    броскиЕсть: Знаки.БРОСКИ.length > 0,
  };
  /* Знак внимания комната кладёт в добавку полуфабрикатом: внутреннее имя
     места и имя игрока. Наружу — только номер, имя и признаки «это я»/
     «в меня», разбираем вручную, как у шашек. */
  const знак = знакДляИгрока(d.знакСырой, key, p?.игроки);
  if (знак) v.знакВнимания = знак;
  if (Array.isArray(d.места)) {
    Object.assign(v, {
      мест: d.мест,
      мойНомер: d.мойНомер,
      яХозяин: !!d.яХозяин,
      можноНачать: !!d.можноНачать,
      парами: false,
      уровеньБотов: d.уровеньБотов,
    });
    v.застолом = d.места.map((m) => ({
      номер: номерМеста(m.ключ),
      имя: m.имя,
      этоЯ: m.ключ === key,
      этоБот: !!m.этоБот,
      хозяин: !!m.хозяин,
      наСвязи: !!m.наСвязи,
      ушёл: !!m.ушёл,
      хочетЕщё: !!m.хочетЕщё,
      напарник: null,
    }));
  }
  if (p && p.игроки.includes(key)) {
    const i = p.игроки.indexOf(key);
    v.монополия = P.view(p.игра, i);
    v.монополия.names = p.игроки.map(
      (k, j) =>
        d.места?.find((m) => m.ключ === k)?.имя ||
        (j === i ? "Вы" : `Игрок ${j + 1}`),
    );
    /* Партия прервана: закончена по согласию стола (server/комнаты.js,
       закончитьПоСогласию) или брошена без итога (результат пуст). Без этого
       признака экран ждал бы хода, которого уже не будет. Признак устроен как
       у деберца: партия, закрытая комнатой с победителем (сдача ушедших),
       не прервана — у неё есть итог, хотя у правил и нет «finished». */
    const поСогласию = !!p.завершена && p.законченаПоСогласию === true;
    v.монополия.прервана = поСогласию || (!!p.завершена && p.результат == null);
  }
  return v;
}
/**
 * Знак внимания для этого игрока: из сырой записи комнаты — только
 * разрешённое. Вместо места приславшего — признак «это я», вместо
 * места цели — «в меня». Тот же приём, что и в server/игры/шашки.js.
 */
function знакДляИгрока(сырое, ктоЯ, игроки) {
  if (!сырое || !Знаки.этоЗнак(сырое.номер)) return null;
  // Порядок игроков партии (как п.игроки у домино) — переводим внутренние
  // ключи «кто»/«цель» в порядковые номера игроков в партии (индекс в p.игроки,
  // не номерМеста), чтобы бросок на экране летел от бросавшего к цели, а не всегда 0 → 1.
  const список = Array.isArray(игроки) ? игроки : [];
  const знак = {
    номер: сырое.номер,
    порядковый: Number(сырое.порядковый) || 0,
    имя: сырое.имя ? String(сырое.имя) : "",
    этоЯ: сырое.кто === ктоЯ,
  };
  if (сырое.кто) знак.от = список.indexOf(сырое.кто);
  if (сырое.цель) {
    знак.цель = сырое.имяЦели ? String(сырое.имяЦели) : "";
    знак.вМеня = сырое.цель === ктоЯ;
    знак.кому = список.indexOf(сырое.цель);
  }
  return знак;
}
