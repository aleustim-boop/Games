"use strict";
const P = require("../../js/монополия-правила"),
  B = require("../../js/монополия-бот"),
  { номерМеста } = require("../партия-по-сети");
/* Знаки внимания — общий набор дурака (смайлики, фразы, броски), тот же,
   что у шашек, нард, домино и деберца: владелец просил «эмоции как
   в дураке». Своего каталога у монополии никогда не было. */
const Знаки = require("../../js/деберц-знаки.js");
function раздать(_, settings = {}) {
  const игроки = (settings.игроки || []).slice();
  if (
    игроки.length < 2 ||
    игроки.length > 6 ||
    new Set(игроки).size !== игроки.length
  )
    throw Error("Нужно 2–6 участников");
  return {
    игроки,
    игра: P.create(игроки.length, undefined, true),
    завершена: false,
    результат: null,
    проигравшие: [],
  };
}
function чейХод(p) {
  return !p || p.завершена ? null : p.игроки[P.who(p.игра)] || null;
}
function сделатьХод(p, key, a = {}) {
  const i = p?.игроки.indexOf(key);
  if (!p || i < 0 || p.завершена)
    return { принято: false, причина: "Партия недоступна" };
  try {
    if (!["монополия", "сдаться"].includes(a.действие))
      throw Error("Неизвестное действие");
    P.action(
      p.игра,
      i,
      a.действие === "сдаться" ? { type: "surrender" } : a.move,
    );
    if (p.игра.phase === "finished") {
      p.завершена = true;
      p.результат = p.игроки[p.игра.winner];
      p.проигравшие = p.игроки.filter((k) => k !== p.результат);
    }
    return { принято: true, событие: a.move?.type || a.действие };
  } catch (e) {
    return { принято: false, причина: e.message };
  }
}
function ходЗаБота(p, key) {
  const i = p.игроки.indexOf(key);
  if (i < 0 || p.завершена) return null;
  const move = B.move(P.view(p.игра, i));
  return move && сделатьХод(p, key, { действие: "монополия", move }).принято
    ? { событие: move.type, ктоСделал: key }
    : null;
}
function видДляИгрока(p, key, d = {}) {
  const v = {
    игра: "монополия",
    код: d.код,
    этап: d.этап,
    версия: d.версия,
    номерСобытия: d.номерСобытия,
    событие: d.событие || "",
    сыграноПартий: d.сыграноПартий,
    яХочуЕщё: !!d.яХочуЕщё,
    соперникХочетЕщё: !!d.соперникХочетЕщё,
    соперникПришёл: !!d.соперникПришёл,
    соперникНаСвязи: !!d.соперникНаСвязи,
    соперникУшёл: !!d.соперникУшёл,
    имяСоперника: String(d.имяСоперника || "Соперник"),
    завершена: !!p?.завершена,
    яХожу: чейХод(p) === key,
    /* Знаки внимания — общий набор дурака (js/деберц-знаки.js). По этим
       признакам экран решает, показывать ли панель «Сказать». */
    знакиВниманияЕсть: Знаки.сколько() > 0,
    броскиЕсть: Знаки.БРОСКИ.length > 0,
  };
  /* Знак внимания комната кладёт в добавку полуфабрикатом: внутреннее имя
     места и имя игрока. Наружу — только номер, имя и признаки «это я»/
     «в меня», разбираем вручную, как у шашек. */
  const знак = знакДляИгрока(d.знакСырой, key);
  if (знак) v.знакВнимания = знак;
  if (Array.isArray(d.места)) {
    Object.assign(v, {
      мест: d.мест,
      мойНомер: d.мойНомер,
      яХозяин: !!d.яХозяин,
      можноНачать: !!d.можноНачать,
      парами: false,
      уровеньБотов: d.уровеньБотов,
    });
    v.застолом = d.места.map((m) => ({
      номер: номерМеста(m.ключ),
      имя: m.имя,
      этоЯ: m.ключ === key,
      этоБот: !!m.этоБот,
      хозяин: !!m.хозяин,
      наСвязи: !!m.наСвязи,
      ушёл: !!m.ушёл,
      хочетЕщё: !!m.хочетЕщё,
      напарник: null,
    }));
  }
  if (p && p.игроки.includes(key)) {
    const i = p.игроки.indexOf(key);
    v.монополия = P.view(p.игра, i);
    v.монополия.names = p.игроки.map(
      (k, j) =>
        d.места?.find((m) => m.ключ === k)?.имя ||
        (j === i ? "Вы" : `Игрок ${j + 1}`),
    );
  }
  return v;
}
/**
 * Знак внимания для этого игрока: из сырой записи комнаты — только
 * разрешённое. Вместо места приславшего — признак «это я», вместо
 * места цели — «в меня». Тот же приём, что и в server/игры/шашки.js.
 */
function знакДляИгрока(сырое, ктоЯ) {
  if (!сырое || !Знаки.этоЗнак(сырое.номер)) return null;
  const знак = {
    номер: сырое.номер,
    порядковый: Number(сырое.порядковый) || 0,
    имя: сырое.имя ? String(сырое.имя) : "",
    этоЯ: сырое.кто === ктоЯ,
  };
  if (сырое.цель) {
    знак.цель = сырое.имяЦели ? String(сырое.имяЦели) : "";
    знак.вМеня = сырое.цель === ктоЯ;
  }
  return знак;
}
