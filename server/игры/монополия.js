"use strict";
const P = require("../../js/монополия-правила"),
  B = require("../../js/монополия-бот"),
  { номерМеста } = require("../партия-по-сети");
function раздать(_, settings = {}) {
  const игроки = (settings.игроки || []).slice();
  if (
    игроки.length < 2 ||
    игроки.length > 6 ||
    new Set(игроки).size !== игроки.length
  )
    throw Error("Нужно 2–6 участников");
  return {
    игроки,
    игра: P.create(игроки.length, undefined, true),
    завершена: false,
    результат: null,
    проигравшие: [],
  };
}
function чейХод(p) {
  return !p || p.завершена ? null : p.игроки[P.who(p.игра)] || null;
}
function сделатьХод(p, key, a = {}) {
  const i = p?.игроки.indexOf(key);
  if (!p || i < 0 || p.завершена)
    return { принято: false, причина: "Партия недоступна" };
  try {
    if (!["монополия", "сдаться"].includes(a.действие))
      throw Error("Неизвестное действие");
    P.action(
      p.игра,
      i,
      a.действие === "сдаться" ? { type: "surrender" } : a.move,
    );
    if (p.игра.phase === "finished") {
      p.завершена = true;
      p.результат = p.игроки[p.игра.winner];
      p.проигравшие = p.игроки.filter((k) => k !== p.результат);
    }
    return { принято: true, событие: a.move?.type || a.действие };
  } catch (e) {
    return { принято: false, причина: e.message };
  }
}
function ходЗаБота(p, key) {
  const i = p.игроки.indexOf(key);
  if (i < 0 || p.завершена) return null;
  const move = B.move(P.view(p.игра, i));
  return move && сделатьХод(p, key, { действие: "монополия", move }).принято
    ? { событие: move.type, ктоСделал: key }
    : null;
}
function видДляИгрока(p, key, d = {}) {
  const v = {
    игра: "монополия",
    код: d.код,
    этап: d.этап,
    версия: d.версия,
    номерСобытия: d.номерСобытия,
    событие: d.событие || "",
    сыграноПартий: d.сыграноПартий,
    яХочуЕщё: !!d.яХочуЕщё,
    соперникХочетЕщё: !!d.соперникХочетЕщё,
    соперникПришёл: !!d.соперникПришёл,
    соперникНаСвязи: !!d.соперникНаСвязи,
    соперникУшёл: !!d.соперникУшёл,
    имяСоперника: String(d.имяСоперника || "Соперник"),
    завершена: !!p?.завершена,
    яХожу: чейХод(p) === key,
  };
  if (Array.isArray(d.места)) {
    Object.assign(v, {
      мест: d.мест,
      мойНомер: d.мойНомер,
      яХозяин: !!d.яХозяин,
      можноНачать: !!d.можноНачать,
      парами: false,
      уровеньБотов: d.уровеньБотов,
    });
    v.застолом = d.места.map((m) => ({
      номер: номерМеста(m.ключ),
      имя: m.имя,
      этоЯ: m.ключ === key,
      этоБот: !!m.этоБот,
      хозяин: !!m.хозяин,
      наСвязи: !!m.наСвязи,
      ушёл: !!m.ушёл,
      хочетЕщё: !!m.хочетЕщё,
      напарник: null,
    }));
  }
  if (p && p.игроки.includes(key)) {
    const i = p.игроки.indexOf(key);
    v.монополия = P.view(p.игра, i);
    v.монополия.names = p.игроки.map(
      (k, j) =>
        d.места?.find((m) => m.ключ === k)?.имя ||
        (j === i ? "Вы" : `Игрок ${j + 1}`),
    );
  }
  return v;
}
module.exports = {
  имя: "монополия",
  мест: { мин: 2, макс: 6, впарах: 0 },
  раздать,
  чейХод,
  сделатьХод,
  видДляИгрока,
  ходЗаБота,
  темпБота: { обычный: 4500, внеОчереди: 4500 },
  ходВнеОчереди: null,
  напарник: () => null,
  знаки: {
    сколько: () => 0,
    этоЗнак: () => false,
    этоБросок: () => false,
    голосБота: () => null,
  },
  текстСобытия: () => "",
};
