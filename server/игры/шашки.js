'use strict';

/* =====================================================================
   ШАШКИ ДЛЯ СЕРВЕРА — вторая игра, которую комната кладёт на стол.

   Своих правил здесь нет ни строчки: и доска, и ходы, и бои, и ничьи
   берутся из js/шашки-правила.js — того же файла, что читает браузер.
   Это то же решение, что и у дурака: правила не раздваиваются, иначе
   сервер и экран однажды разойдутся в решениях, и такую ошибку будут
   искать неделю.

   ЧТО ЗДЕСЬ ЕСТЬ. Перевод с языка комнаты («место за столом», «ход
   игрока», «вид для игрока») на язык шашек («цвет», «ход», «доска»)
   и обратно. Договор, по которому комната разговаривает с игрой,
   описан в server/игры/реестр.js.

   «КЛИЕНТУ НЕ ВЕРИМ» И ЗДЕСЬ. Доска у шашек открыта обоим, прятать
   нечего — но правило остаётся: вид собирается вручную, поле за полем
   (см. видДляИгрока), а ход проверяется правилами на сервере. Иначе
   вместе с доской наружу уехало бы то, чего игроку видеть нельзя:
   у бота — его план и оценка позиции, а в будущих шахматах — заранее
   посчитанный ответ соперника.

   ЦВЕТА ПО МЕСТАМ. Первое место — белые, второе — чёрные; первый ход
   всегда за белыми. Кто именно сядет белыми, решает комната: на реванше
   она называет начинающего, и он получает белых.
   ===================================================================== */

const Правила = require('../../js/шашки-правила.js');
const Бот = require('../../js/шашки-бот.js');
const Знаки = require('../../js/шашки-знаки.js');

/* За доской ровно двое, и пар не бывает. Число мест берёт отсюда сама
   комната: её прежние «от двух до шести» — это правила дурака. */
const МЕСТ_ЗА_ДОСКОЙ = 2;

/* Сколько бот «думает» перед ходом. Та же пауза, что у дурака: ход,
   который случается мгновенно, человек не успевает заметить. */
const ПАУЗА_БОТА = 700;

/* Сколько бот думает НА СЕРВЕРЕ. В браузере у сложного уровня 300 мс,
   и там это правильно: стол один, экран всё равно ждёт хода. На сервере
   столов много, а счёт идёт синхронно — эти 300 мс тормозят разом всех,
   кто в эту секунду ходит за другими столами. Половина бюджета выбрана
   так, чтобы разница между уровнями сохранилась: за 150 мс перебор уходит
   заметно глубже, чем у обычного уровня (тот считает около 25 мс). */
const БЮДЖЕТ_НА_СЕРВЕРЕ = 150;

/**
 * Раздать — то есть расставить шашки и назначить цвета.
 *
 * Партия наружу выглядит одинаково у всех игр сервера: комната смотрит
 * в неё ровно четырьмя полями — «игроки», «завершена», «результат»,
 * «проигравшие», — и они здесь есть. Всё остальное (доска, цвета,
 * последний ход) читает только этот файл.
 */
function раздать(ктоНачинает, настройки) {
  const все = (настройки && Array.isArray(настройки.игроки) ? настройки.игроки : [])
    .slice(0, МЕСТ_ЗА_ДОСКОЙ);
  /* Белые — тот, кого комната назвала начинающим: у неё это проигравший
     прошлой партии, и ему честно достаётся первый ход. Не назвала или
     назвала того, кого за доской нет, — белыми садится первый по столу. */
  const белые = все.indexOf(ктоНачинает) !== -1 ? ктоНачинает : все[0];
  const чёрные = все.filter(function (место) { return место !== белые; })[0] || null;

  const цвета = {};
  if (белые) цвета[белые] = Правила.БЕЛЫЕ;
  if (чёрные) цвета[чёрные] = Правила.ЧЁРНЫЕ;

  return {
    игроки: все,
    завершена: false,
    результат: null,
    проигравшие: [],
    цвета: цвета,
    доска: Правила.создатьПартию(),
    /* Последний ход целиком — с путём и побитыми. Без пути чужой бой
       выглядит телепортацией: шашка исчезла тут и появилась там, а через
       какие поля она прошла и кого сняла — не видно. */
    последнийХод: null
  };
}

/** Место, которое играет этим цветом. */
function местоЦвета(партия, цвет) {
  for (const место of партия.игроки) {
    if (партия.цвета[место] === цвет) return место;
  }
  return null;
}

/** Чей сейчас ход — внутреннее имя места или null, если партия кончилась. */
function чейХод(партия) {
  if (!партия || партия.завершена) return null;
  return местоЦвета(партия, Правила.чейХод(партия.доска));
}

/**
 * Записать итог в саму партию: комната читает его этими же полями
 * у любой игры (см. учестьИтогПартии и выйти в server/комнаты.js).
 */
function записатьИтог(партия) {
  if (!Правила.партияЗавершена(партия.доска)) return;
  const итог = Правила.итог(партия.доска);
  партия.завершена = true;
  if (!итог || итог.ничья) {
    партия.результат = null;      // ничья: проигравших нет
    партия.проигравшие = [];
    партия.ничья = true;
    партия.причинаКонца = итог ? итог.причина : null;
    return;
  }
  const победитель = местоЦвета(партия, итог.победитель);
  партия.результат = победитель;
  партия.проигравшие = партия.игроки.filter(function (место) {
    return место !== победитель;
  });
  партия.ничья = false;
  партия.причинаКонца = итог.причина;
}

/**
 * Ход игрока. Принимаем ровно тот вид, который понимают правила:
 * { откуда, куда, побитые?, станетДамкой? }.
 *
 * Ход НЕ доверяем: правила сами ищут среди законных единственный
 * подходящий (найтиХод) и сами снимают побитые. Присланный список
 * побитых — только уточнение, когда одними полями ход не различить.
 */
function сделатьХод(партия, ктоЯ, намерение) {
  if (!партия || партия.завершена) {
    return { принято: false, причина: 'Партия уже закончена' };
  }
  const действие = намерение && typeof намерение.действие === 'string'
    ? намерение.действие : '';
  /* Ничья по соглашению — три отдельных действия той же дверью «/ход».
     Живут они здесь, а не в комнате, нарочно: ничья — правило игры,
     а не устройство стола, и у карт её нет вовсе. */
  if (действие === 'ничья') return предложитьНичью(партия, ктоЯ);
  if (действие === 'ничья-да') return ответитьНаНичью(партия, ктоЯ, true);
  if (действие === 'ничья-нет') return ответитьНаНичью(партия, ктоЯ, false);

  if (действие !== 'ход') {
    return { принято: false, причина: 'В шашках так не ходят' };
  }
  if (чейХод(партия) !== ктоЯ) {
    return { принято: false, причина: 'Сейчас не ваш ход' };
  }

  const просят = {
    откуда: намерение.откуда,
    куда: намерение.куда,
    побитые: Array.isArray(намерение.побитые) ? намерение.побитые : undefined,
    станетДамкой: typeof намерение.станетДамкой === 'boolean'
      ? намерение.станетДамкой : undefined
  };

  /* Ход берём у правил ЦЕЛИКОМ и до того, как он сделан: в нём лежит путь
     и список побитых, а после хода спросить об этом будет негде. */
  const ход = Правила.найтиХод(партия.доска, просят);
  if (!ход) return { принято: false, причина: почемуНельзя(партия, просят) };

  if (!Правила.сделатьХод(партия.доска, ход)) {
    /* Сюда попасть нельзя: ход только что был среди законных. Если всё же
       попали — молчать нельзя, иначе стол встанет без объяснений. */
    return { принято: false, причина: 'Этот ход не получился — попробуйте другой' };
  }

  /* Сходил — значит, ответил на предложение делом: висящую просьбу
     о ничьей снимаем. Иначе она пережила бы ход и человек согласился
     бы на ничью уже в другой позиции. */
  партия.ничьяПредложена = null;

  партия.последнийХод = {
    откуда: ход.откуда,
    куда: ход.куда,
    путь: ход.путь.slice(),
    побитые: ход.побитые.slice(),
    бой: ход.бой === true,
    чей: ктоЯ
  };
  записатьИтог(партия);

  return { принято: true, событие: ход.бой ? 'бой' : 'ход' };
}

/* ---------------------------------------------------------------------
   НИЧЬЯ ПО СОГЛАШЕНИЮ

   Зачем. Правила ничью умеют — три автоматических счётчика, — но пока
   они сработают, две дамки могут гонять друг друга полсотни ходов.
   Сказать «давай на этом закончим» было нечем: человек хотел, а игра
   не давала.

   Как устроено. Предложение живёт ВНУТРИ партии, и это закрывает два
   случая, которые легко забыть: соперник ушёл (за доской двое — комната
   завершает партию, и предложение уходит вместе с ней) и партия кончилась
   сама (у завершённой партии вид предложения не отдаёт вовсе).

   Частота — по полуходам, а не по времени: время можно пересидеть, ходы
   нет. После отказа следующее предложение — не раньше чем через шесть
   полуходов, то есть три хода каждой стороны. Иначе повторными просьбами
   удобно мешать сопернику думать, а это уже не просьба о ничьей.
   --------------------------------------------------------------------- */

/* Сколько полуходов ждать после отказа. Три хода каждой стороны — за это
   время позиция успевает измениться, и вторая просьба уже про другое. */
const ЖДАТЬ_ПОСЛЕ_ОТКАЗА = 6;

/** Сколько полуходов сыграно — по ним и считаем частоту предложений. */
function сколькоПолуходов(партия) {
  return партия && партия.доска ? Number(партия.доска.полуходов) || 0 : 0;
}

/** Можно ли сейчас предлагать ничью и почему нет. */
function почемуНельзяПредлагать(партия, ктоЯ) {
  if (партия.завершена) return 'Партия уже закончена';
  if (партия.игроки.indexOf(ктоЯ) === -1) return 'Вас нет за этой доской';
  if (партия.ничьяПредложена) {
    return партия.ничьяПредложена.кто === ктоЯ
      ? 'Вы уже предложили ничью — ждём ответа'
      : 'Соперник сам предложил ничью — ответьте на его предложение';
  }
  const отказ = партия.ничьяОтказ;
  if (отказ && отказ.кому === ктоЯ) {
    const прошло = сколькоПолуходов(партия) - отказ.наПолуходе;
    if (прошло < ЖДАТЬ_ПОСЛЕ_ОТКАЗА) {
      const осталось = Math.ceil((ЖДАТЬ_ПОСЛЕ_ОТКАЗА - прошло) / 2);
      return 'Соперник только что отказался. Предложить снова можно через ' +
             осталось + (осталось === 1 ? ' ход' : ' хода');
    }
  }
  return '';
}

/** Предложить ничью сопернику. */
function предложитьНичью(партия, ктоЯ) {
  const нельзя = почемуНельзяПредлагать(партия, ктоЯ);
  if (нельзя) return { принято: false, причина: нельзя };
  партия.ничьяПредложена = { кто: ктоЯ, наПолуходе: сколькоПолуходов(партия) };
  return { принято: true, событие: 'ничья-предложена' };
}

/**
 * Ответить на предложение. Согласие заканчивает партию вничью — тем же
 * итогом, каким её заканчивают правила, чтобы дальше по дороге (рейтинг,
 * статистика, экран) ничья была одна и та же, а не двух сортов.
 *
 * Отказ ничего не объявляет: партия просто продолжается. Предложившему
 * скажут об этом короткой строкой, и на этом всё.
 */
function ответитьНаНичью(партия, ктоЯ, согласен) {
  const предложение = партия.ничьяПредложена;
  if (!предложение) return { принято: false, причина: 'Ничью никто не предлагал' };
  if (предложение.кто === ктоЯ) {
    return { принято: false, причина: 'Это ваше предложение — ответить может соперник' };
  }
  партия.ничьяПредложена = null;

  if (!согласен) {
    /* Помним, КОМУ отказали: ждать шесть полуходов должен тот, кому
       сказали «нет», а не тот, кто отказал. */
    партия.ничьяОтказ = { кому: предложение.кто, наПолуходе: сколькоПолуходов(партия) };
    return { принято: true, событие: 'ничья-отклонена' };
  }

  партия.завершена = true;
  партия.результат = null;
  партия.проигравшие = [];
  партия.ничья = true;
  партия.причинаКонца = 'по соглашению';
  return { принято: true, событие: 'ничья-согласие' };
}

/**
 * Почему ход не подошёл — словами, а не «так нельзя».
 * Разбираем три частых случая: не своя шашка, бить обязательно,
 * и «полей мало» (одними полями ход не различить).
 */
function почемуНельзя(партия, просят) {
  const ходы = Правила.возможныеХоды(партия.доска);
  const сЭтогоПоля = ходы.filter(function (х) { return х.откуда === просят.откуда; });

  if (Правила.естьБой(партия.доска) && ходы.every(function (х) { return х.бой; })) {
    if (сЭтогоПоля.length === 0) {
      return 'Бить обязательно — этой шашкой сейчас нельзя';
    }
  }
  if (сЭтогоПоля.length === 0) {
    return 'Этой шашкой сюда не пойти';
  }
  const туда = сЭтогоПоля.filter(function (х) { return х.куда === просят.куда; });
  if (туда.length === 0) return 'Так эта шашка не ходит';
  return 'Тут несколько разных боёв — укажите, какие шашки снимаете';
}

/**
 * Ход за бота — теми же правилами, что и ход человека.
 *
 * Думает настоящий бот шашек (js/шашки-бот.js), а не какая-то серверная
 * его копия: копия — это второй набор решений, который однажды разойдётся
 * с тем, что человек видел в игре против бота на своём телефоне.
 *
 * Ход бота идёт через ту же дверь «сделатьХод», что и ход человека:
 * значит, законность его хода проверяется ровно так же.
 */
function ходЗаБота(партия, место, уровень) {
  if (!партия || партия.завершена) return null;
  if (чейХод(партия) !== место) return null;

  const выбранный = Бот.выбратьХодСразу(партия.доска, {
    уровень: уровень || Бот.УРОВЕНЬ_ПО_УМОЛЧАНИЮ,
    бюджетМс: БЮДЖЕТ_НА_СЕРВЕРЕ
  });
  if (!выбранный) return null;

  const ответ = сделатьХод(партия, место, {
    действие: 'ход',
    откуда: выбранный.откуда,
    куда: выбранный.куда,
    побитые: выбранный.побитые,
    станетДамкой: выбранный.станетДамкой
  });
  if (!ответ.принято) return null;

  /* Бот иногда говорит и кидает — тем же путём, что у дурака: комната
     запишет этот знак сама, разбирать его здесь нечего. Цель у броска
     одна и та же всегда: за доской двое, значит соперник — единственное
     другое место. Годится ли эта цель (за столом ли он, не ушёл ли),
     решает комната, а не мы. */
  const соперник = партия.игроки.filter(function (кто) { return кто !== место; })[0] || null;
  const бросок = соперник ? Знаки.бросокБота() : null;
  return {
    событие: ответ.событие,
    ктоСделал: место,
    /* За один ход уходит один знак: бросок важнее слова, поэтому,
       если бот кинул, говорить он уже не станет. */
    эмоция: бросок ? null : Знаки.знакБота(),
    бросок: бросок ? { номер: бросок.номер, цель: соперник } : null
  };
}

/**
 * Что видит этот игрок. Собираем вручную, поле за полем, — и то, что
 * пришло от комнаты, тоже перебираем по одному: служебные полуфабрикаты
 * (сырое событие, сырой список мест) наружу уходить не должны.
 */
function видДляИгрока(партия, ктоЯ, добавка) {
  const пришло = добавка || {};
  const места = Array.isArray(пришло.места) ? пришло.места : [];

  const вид = {
    игра: 'шашки',
    код: пришло.код,
    этап: пришло.этап,
    версия: пришло.версия,
    номерСобытия: пришло.номерСобытия,
    событие: пришло.событие || '',
    /* Короткое слово события из закрытого набора: «ход», «бой», «вошёл»,
       «ничья-предложена», «ничья-отклонена», «ничья-согласие». Экран
       читает именно его, а не текст: текст написан для человека и
       меняется вместе со словами игры, а решения по нему принимать
       нельзя — от правки формулировки экран ослеп бы молча. Ни имён,
       ни внутренних названий мест в этом слове нет. */
    видСобытия: пришло.событиеСырое && typeof пришло.событиеСырое.что === 'string'
      ? пришло.событиеСырое.что : '',
    /* Имя того, с кем событие случилось. Ленте оно нужно отдельно от текста:
       она строит свои строки и разбирать чужую фразу не должна. Имя то же,
       что видно за столом, — ничего нового наружу не уходит. */
    имяСобытия: пришло.событиеСырое && пришло.событиеСырое.имя
      ? String(пришло.событиеСырое.имя) : '',
    сыграноПартий: пришло.сыграноПартий,
    яХочуЕщё: пришло.яХочуЕщё === true,
    соперникХочетЕщё: пришло.соперникХочетЕщё === true,
    соперникПришёл: пришло.соперникПришёл === true,
    соперникНаСвязи: пришло.соперникНаСвязи === true,
    соперникУшёл: пришло.соперникУшёл === true,
    мест: пришло.мест,
    мойНомер: пришло.мойНомер,
    яХозяин: пришло.яХозяин === true,
    можноНачать: пришло.можноНачать === true,
    /* Знаков внимания у шашек пока нет вовсе, и говорим об этом прямо:
       по этому признаку игра решает, показывать ли кнопку смайликов. */
    /* Знаки внимания у шашек есть: смайлики и броски — те же, что у карт,
       фразы свои (см. js/шашки-знаки.js). По этим признакам экран решает,
       показывать ли панель. */
    знакиВниманияЕсть: Знаки.сколькоЗнаков() > 0,
    броскиЕсть: Знаки.БРОСКИ.length > 0,
    застолом: места.map(function (место) {
      return {
        номер: место.номер,
        имя: место.имя,
        этоЯ: место.ключ === ктоЯ,
        этоБот: место.этоБот === true,
        хозяин: место.хозяин === true,
        наСвязи: место.наСвязи !== false,
        ушёл: место.ушёл === true,
        хочетЕщё: место.хочетЕщё === true,
        /* Цвет — единственное, что добавляют шашки к общей плашке места.
           Пока не раздали, цвета ещё нет: он назначается при раздаче. */
        цвет: партия && партия.цвета ? (партия.цвета[место.ключ] || null) : null
      };
    })
  };

  /* Знак внимания комната кладёт в добавку полуфабрикатом: в нём лежит
     внутреннее имя места («первый») и имя игрока. Наружу из него уходят
     только номер, имя приславшего и признаки «это я» и «в меня» —
     разбираем вручную, поле за полем, как везде. */
  const знак = знакДляИгрока(пришло.знакСырой, ктоЯ);
  if (знак) вид.знакВнимания = знак;

  if (!партия) return вид;

  /* Номер кресла соперника. Нужен броску: он летит в человека, и адресата
     называют креслом. Спрашивать его у списка мест нельзя — за столом
     на двоих комната списка не присылает вовсе (он есть только у компании
     с прихожей). За доской мест ровно два, первое и второе, поэтому кресло
     — это место игрока по порядку. */
  /* Ничья по соглашению: что видит этот игрок. У завершённой партии
     предложения не бывает вовсе — так закрывается случай «партия кончилась,
     пока предложение висело». */
  const предложение = партия.завершена ? null : партия.ничьяПредложена;
  if (предложение) {
    вид.предложениеНичьей = {
      моё: предложение.кто === ктоЯ,
      ждётМеня: предложение.кто !== ктоЯ
    };
  }
  вид.можноПредложитьНичью = почемуНельзяПредлагать(партия, ктоЯ) === '';

  const соперникЗаДоской = партия.игроки.filter(function (кто) { return кто !== ктоЯ; })[0];
  if (соперникЗаДоской) {
    вид.креслоСоперника = партия.игроки.indexOf(соперникЗаДоской) + 1;
  }

  const ходит = чейХод(партия);
  вид.доска = Правила.картинкаПартии(партия.доска);
  вид.чейХод = партия.завершена ? null : Правила.чейХод(партия.доска);
  вид.мойЦвет = партия.цвета[ктоЯ] || null;
  вид.яХожу = ходит === ктоЯ;
  вид.естьБой = партия.завершена ? false : Правила.естьБой(партия.доска);
  вид.завершена = партия.завершена === true;

  /* Последний ход — с полным путём: только по нему видно, как шёл чужой
     бой. Имя места («первый») наружу не отдаём, отдаём признак «мой». */
  if (партия.последнийХод) {
    вид.последнийХод = {
      откуда: партия.последнийХод.откуда,
      куда: партия.последнийХод.куда,
      путь: партия.последнийХод.путь.slice(),
      побитые: партия.последнийХод.побитые.slice(),
      бой: партия.последнийХод.бой === true,
      /* Чей это был ход — ЦВЕТОМ. Именно по цвету экран решает, проигрывать
         ли чужой бой по клеткам: он сверяет его со своей доской, а внутренних
         имён мест у него нет и быть не должно. Пока здесь стоял только
         признак «мой», условие на экране не сходилось никогда, и чужой бой
         молча показывался разом — той самой телепортацией, на которую
         жаловался владелец. Ошибки при этом не было ни одной. */
      чей: партия.цвета[партия.последнийХод.чей] || null,
      мой: партия.последнийХод.чей === ктоЯ
    };
  }

  if (партия.завершена) {
    вид.итог = {
      победитель: партия.результат ? партия.цвета[партия.результат] || null : null,
      ничья: партия.ничья === true,
      причина: партия.причинаКонца || null,
      яВыиграл: Boolean(партия.результат) && партия.результат === ктоЯ
    };
  }

  return вид;
}

/**
 * Знак внимания для этого игрока: из сырой записи комнаты — только
 * разрешённое. Внутренних имён мест здесь не остаётся: вместо места
 * приславшего — признак «это я», вместо места цели — «в меня».
 */
function знакДляИгрока(сырое, ктоЯ) {
  if (!сырое || !Знаки.этоЗнак(сырое.номер)) return null;
  const знак = {
    номер: сырое.номер,
    порядковый: Number(сырое.порядковый) || 0,
    имя: сырое.имя ? String(сырое.имя) : '',
    этоЯ: сырое.кто === ктоЯ
  };
  if (сырое.цель) {
    знак.цель = сырое.имяЦели ? String(сырое.имяЦели) : '';
    знак.вМеня = сырое.цель === ктоЯ;
  }
  return знак;
}

/** Рассказ о ходе словами — короткая шашечная запись, вроде «c3:e5:c7». */
function текстСобытия(событие, ктоЯ, места, этоКомпания, подробности) {
  if (!событие || !событие.что) return '';
  const своё = событие.кто === ктоЯ;
  const имя = своё ? 'Вы' : (событие.имя || 'Соперник');

  /* НИ ОДНОГО ГЛАГОЛА ПРОШЕДШЕГО ВРЕМЕНИ про соперника. Русский глагол
     в прошедшем согласуется с родом, а рода мы не знаем и узнать не можем:
     в имени его нет, Telegram нам его не сообщает, а имена бывают любые.
     «Боря вышла» или «Аня побил» — это то, что человек прочтёт как
     неряшливость игры. Поэтому здесь либо настоящее время (рода не
     требует), либо вовсе без глагола. Тот же приём мы уже применили
     в рейтинге: «Ничья: Мария» вместо «Ничья с Мария». */
  if (событие.что === 'ход') return имя + ': ход';
  if (событие.что === 'бой') return имя + ': бой';
  if (событие.что === 'ничья-предложена') return имя + ' предлагает ничью';
  if (событие.что === 'ничья-отклонена') {
    return своё ? 'Вы играете дальше' : 'Соперник хочет играть дальше';
  }
  if (событие.что === 'ничья-согласие') return 'Ничья по соглашению';
  if (событие.что === 'вошёл') return имя + ' за доской';
  if (событие.что === 'ушёл' || событие.что === 'ушёл-из-комнаты') {
    return имя + ' больше не играет';
  }
  return '';
}

