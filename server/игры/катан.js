function раздать(_,настройки={}){
  const игроки=(настройки.игроки||[]).slice();
  if(![3,4].includes(игроки.length)||new Set(игроки).size!==игроки.length)throw Error('Для Катана нужно 3 или 4 игрока');
  const игра=П.создать(игроки.length,undefined,true,3,настройки.катанНастройки);
  return {игроки,игра,часы:Ч.обновить({},игра),завершена:false,результат:null,проигравшие:[]};
}
function чейХод(п){return !п||п.завершена?null:п.игроки[П.кто(п.игра)]||null;}
function сделатьХод(п,кто,н={}){
  const i=п?.игроки.indexOf(кто);if(!п||i<0||п.завершена)return {принято:false,причина:'Партия недоступна'};
  try{
    if(н.действие==='сдаться'){
      п.завершена=true;п.проигравшие=[кто];п.результат=п.игроки.find(x=>x!==кто);п.сдался=i;
    }else{
      if(н.действие!=='катан')throw Error('Неизвестное действие');
      if(н.move?.type==='surrender')throw Error('Используйте действие «сдаться»');
      if(н.move?.type==='undo'&&Ч.остаток(п.часы)<=0)throw Error('Время хода истекло');
      П.действие(п.игра,i,н.move);
      Ч.обновить(п.часы||={},п.игра);
      if(п.игра.phase==='finished'){п.завершена=true;п.результат=п.игроки[п.игра.winner];п.проигравшие=п.игроки.filter(x=>x!==п.результат);}
    }
    return {принято:true,событие:н.действие==='катан'?н.move.type:н.действие};
  }catch(e){return {принято:false,причина:e.message};}
}
function ходЗаБота(п,кто,уровень='обычный'){
  const i=п.игроки.indexOf(кто);if(i<0||п.завершена)return null;
  const move=Б.ход(П.вид(п.игра,i),уровень);
  return move&&сделатьХод(п,кто,{действие:'катан',move}).принято?{событие:move.type,ктоСделал:кто}:null;
}
function видДляИгрока(п,кто,d={}){
  const v={игра:'катан',код:d.код,этап:d.этап,версия:d.версия,номерСобытия:d.номерСобытия,событие:d.событие||'',сыграноПартий:d.сыграноПартий,
    катанНастройки:П.настройки(d.катанНастройки||п?.игра.options),
    яХочуЕщё:!!d.яХочуЕщё,соперникХочетЕщё:!!d.соперникХочетЕщё,соперникПришёл:!!d.соперникПришёл,соперникНаСвязи:!!d.соперникНаСвязи,соперникУшёл:!!d.соперникУшёл,
    имяСоперника:String(d.имяСоперника||'Соперник'),завершена:!!п?.завершена,яХожу:чейХод(п)===кто};
  if(Array.isArray(d.места)){
    Object.assign(v,{мест:d.мест,мойНомер:d.мойНомер,яХозяин:!!d.яХозяин,можноНачать:!!d.можноНачать,парами:false,уровеньБотов:d.уровеньБотов});
    v.застолом=d.места.map(m=>({номер:номерМеста(m.ключ),имя:m.имя,этоЯ:m.ключ===кто,этоБот:!!m.этоБот,хозяин:!!m.хозяин,наСвязи:!!m.наСвязи,ушёл:!!m.ушёл,хочетЕщё:!!m.хочетЕщё,напарник:null}));
  }
  if(п&&п.игроки.includes(кто)){
    const i=п.игроки.indexOf(кто);v.катан=П.вид(п.игра,i);
    v.катан.names=п.игроки.map((key,j)=>d.места?.find(m=>m.ключ===key)?.имя||(j===i?'Вы':`Игрок ${j+1}`));
    const seconds=Ч.остаток(п.часы);v.катан.secondsLeft=п.завершена||!Number.isFinite(seconds)?null:seconds;
    if(п.завершена&&п.игра.phase!=='finished'){v.катан.phase='finished';v.катан.winner=-1;v.катан.interrupted=true;v.катан.surrendered=п.сдался??-1;}
  }
  return v;
}
