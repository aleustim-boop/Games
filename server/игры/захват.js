/* Обычная Error из правил уже по-русски — показываем как есть. Техническую
   ошибку JS (TypeError и прочие) игрок не видит: пишем её в журнал, а ему —
   общие слова (так же сделано у домино). */
function понятнаяПричина(e, где) {
  if (e instanceof Error && e.constructor === Error) return e.message;
  console.error(где + ': сбой хода', e);
  return 'Такой ход не принят';
}

function отказ(причина) { return { принято: false, причина: причина }; }

/* Единственные источники времени и случая. Проверка подменяет
   module.exports.сейчас и module.exports.случай, чтобы партия шла
   предсказуемо и без ожидания. */
function сейчас() { return module.exports.сейчас(); }
function случай() { return module.exports.случай(); }

/* Уровень бота приходит из комнаты словом. Незнакомое слово — обычный бот:
   стол не должен вставать из-за опечатки в настройке. */
function уровеньБота(уровень) {
  return Б.УРОВНИ.indexOf(уровень) !== -1 ? уровень : 'обычный';
}

/* Время раунда (ТЗ 3.6): 40 или 60 секунд, всё прочее — 60. */
function секундНаРаунд(лимит) {
  const числа = П.ЧИСЛА.секундНаРаунд;
  const секунд = Number(лимит);
  return секунд === числа.быстро || секунд === числа.обычно ? секунд : числа.обычно;
}

/* Разбор правил отдаёт НОВУЮ партию (правила партию не меняют). Комната же
   держит ссылку на старый объект — поэтому переносим состояние в него.

   Правила копируют партию через JSON. Отсюда два обязательства для всего,
   что этот файл кладёт в партию:
   - поля партии обязаны храниться в JSON: только числа, строки, true/false,
     null, массивы и простые объекты. Никаких Infinity (станет null), дат
     (станут строкой), функций и undefined (пропадут после первого разбора);
   - ссылки на вложенные части партии (партия.черновики, партия.готовКто…)
     через разбор держать нельзя: после разбора это уже другие объекты, и
     запись в старую ссылку молча уйдёт в никуда. Каждый раз брать заново
     от партии. */
function перенестиСостояние(партия, новая) {
  Object.keys(партия).forEach(function (ключ) {
    if (!(ключ in новая)) delete партия[ключ];
  });
  Object.assign(партия, новая);
}

/* ---------------------------------------------------------------------
   И17. Раздача. ктоНачинает «Захвату» не нужен — ходят все разом.
   --------------------------------------------------------------------- */
function раздать(ктоНачинает, настройки = {}) {
  const игроки = (настройки.игроки || []).slice();
  const мест = П.ЧИСЛА.мест;
  if (игроки.length < мест.мин || игроки.length > мест.макс || new Set(игроки).size !== игроки.length) {
    throw Error('Нужно от ' + мест.мин + ' до ' + мест.макс + ' игроков');
  }
  /* Люди за картой (К11): от них зависит правило «все люди выбыли» (ТЗ 5).
     Посторонние ключи отбрасываем — человеком может быть только сидящий. */
  const люди = Array.isArray(настройки.люди)
    ? настройки.люди.filter(function (к) { return игроки.indexOf(к) !== -1; })
    : [];
  /* Первой партии новичка (ТЗ 13) онлайн не бывает — новичок не передаётся.
     Длину партии выбирает хозяин: 10, 15, 20 раундов или 'победа' («До
     победы», ТЗ 5а); правила сами читают это поле и сверяют со списком. */
  const партия = П.новаяПартия({
    игроки: игроки, люди: люди, сейчас: сейчас(), раундовЗахвата: настройки.раундовЗахвата
  }, случай);
  партия.хозяин = игроки.indexOf(настройки.хозяин) !== -1 ? настройки.хозяин : игроки[0];
  партия.секундНаРаунд = секундНаРаунд(настройки.лимитСекундНаХод);
  партия.готовКто = {};      // {ключ: 'сам' | 'бот'} — кто нажал «Готово» в этом раунде
  партия.ботГотовВ = {};     // миги ботов (И8, этап А9а)
  партия.разобранВ = null;   // миг последнего разбора (И5); в первом раунде его нет
  партия.события = [];       // события последнего разобранного раунда
  партия.раундСобытий = null;
  партия.хозяеваДоРазбора = null; // карта до последнего разбора — для раскрытия после перезагрузки
  партия.войскаДоРазбора = null;  // войска до последнего разбора — по ним браузер рисует «было → стало»
  партия.результат = null;
  партия.проигравшие = [];
  партия.ничья = false;
  партия.итог = null;
  return партия;
}

/* И12. Очереди нет. */
function чейХод() { return null; }

/* И11. Выбывшее и сдавшееся кнопкой место — вне игры; ушедшее — в игре (его водит бот). */
function вИгре(партия, место) {
  return !!партия && Array.isArray(партия.игроки) && партия.игроки.indexOf(место) !== -1 && П.вИгре(партия, место);
}

/* ---------------------------------------------------------------------
   И1. Опоздавшая дверь. «Готово», «Изменить» и черновик несут номер
   раунда; не тот номер или его нет — отказ. Ничего не меняет.
   Пропускаем без сверки только ходы, названные словом, кроме «готово» и
   «изменить» («сдаться», фраза…). Всё, где «действие» не строка (нет поля,
   null, число), сверяем: иначе старый черновик с «действие: null» прошёл бы
   мимо сверки раунда (замечание ревью А8).
   --------------------------------------------------------------------- */
function устаревшийХод(партия, место, намерение) {
  if (!партия || !намерение || typeof намерение !== 'object') return null;
  const действие = намерение.действие;
  const сверять = typeof действие !== 'string' || действие === 'готово' || действие === 'изменить';
  if (!сверять) return null;
  if (Number.isInteger(намерение.раунд) && намерение.раунд === партия.раунд) return null;
  return { принято: false, причина: 'Раунд уже разыгран', устарел: true };
}

/* «Готово» (И15): остаток подкрепления ставится по правилу 3.3 — вопрос
   об остатке браузер задаёт до отправки. ✓ «сам» ставит только эта дверь. */
function нажатьГотово(партия, место) {
  if (!П.вИгре(партия, место)) return отказ('Вы уже не в игре');
  if (партия.готовКто[место]) return отказ('«Готово» уже нажато');
  const черновик = П.остатокПоПросрочке(партия, место, партия.черновики[место]);
  const проверка = П.проверитьЧерновик(партия, место, черновик);
  if (!проверка.принято) return отказ(проверка.причина);
  партия.черновики[место] = черновик;
  партия.готовКто[место] = 'сам';
  return { принято: true, событие: 'готово' };
}

/* «Изменить» (И15): снять ✓ и забыть, кто его ставил, — при уходе такой
   черновик считается ненажатым (И9). Черновик остаётся как есть. */
function нажатьИзменить(партия, место) {
  if (!П.вИгре(партия, место)) return отказ('Вы уже не в игре');
  if (!партия.готовКто[место]) return отказ('«Готово» ещё не нажато');
  delete партия.готовКто[место];
  return { принято: true, событие: 'изменить' };
}

/* «Сдаться» (И15, ТЗ 3.8): номер раунда не нужен. Правила сами проверят
   конец партии и, если живым осталось одно место, запишут итог по 15.2. */
function сдатьсяХодом(партия, место) {
  const ответ = П.сдаться(партия, место);
  if (!ответ.принято) return отказ(ответ.причина);
  return { принято: true, событие: 'сдался' };
}

/* И15. Обычные ходы: «готово», «изменить», «сдаться». Черновик сюда не
   ходит — у него своя тихая дверь (принятьЧерновик, этап А9а). */
function сделатьХод(партия, место, намерение) {
  if (!партия || !Array.isArray(партия.игроки) || партия.игроки.indexOf(место) === -1) return отказ('Партия недоступна');
  if (партия.завершена) return отказ('Партия уже окончена');
  if (!намерение || typeof намерение !== 'object') return отказ('Ход не разобран');
  const опоздал = устаревшийХод(партия, место, намерение);
  if (опоздал) return опоздал;
  try {
    if (намерение.действие === 'готово') return нажатьГотово(партия, место);
    if (намерение.действие === 'изменить') return нажатьИзменить(партия, место);
    if (намерение.действие === 'сдаться') return сдатьсяХодом(партия, место);
  } catch (e) {
    return отказ(понятнаяПричина(e, 'захват'));
  }
  return отказ('Такого хода в «Захвате» нет');
}

/* ---------------------------------------------------------------------
   И2. Тихая дверь черновика (ТЗ 15.2): черновик целиком заменяет прежний.
   Отдаёт { принято, причина, черновик } — черновик как он сохранён (копия:
   ссылку на партию наружу не даём). Ответ уходит только приславшему, так
   что свой сохранённый черновик в нём — не тайна.
   --------------------------------------------------------------------- */
function копияЧерновика(черновик) {
  return черновик ? JSON.parse(JSON.stringify(черновик)) : П.пустойЧерновик();
}

function ответЧерновика(партия, место, причина) {
  return { принято: причина === null, причина: причина, черновик: копияЧерновика(партия.черновики[место]) };
}

/* Из присланного берём только расстановку и приказы, приказ — только из, в,
   сколько: лишние поля браузера в партию не попадают. Проверка 3.4 смотрит
   ровно то, что потом сохранится. */
function чистыйЧерновик(черновик) {
  const расстановка = черновик.расстановка === undefined ? {} : черновик.расстановка;
  const приказы = черновик.приказы === undefined ? [] : черновик.приказы;
  return {
    расстановка: расстановка,
    приказы: Array.isArray(приказы)
      ? приказы.map(function (п) {
          return п && typeof п === 'object' ? { из: п.из, в: п.в, сколько: п.сколько } : п;
        })
      : приказы
  };
}

/* Номер области в расстановке — ключ-строка. Правила читают его через
   Number(), и тогда «01», «1.0» и «0x1» стали бы той же областью 1: в
   партии лёг бы ключ, которого нет на карте. Берём только простейшую запись. */
function номераОбластейПросты(черновик) {
  const расстановка = черновик.расстановка;
  if (!расстановка || typeof расстановка !== 'object' || Array.isArray(расстановка)) return true;
  return Object.keys(расстановка).every(function (к) { return String(Number(к)) === к; });
}

/* Условие для этой двери (ревью Б3ф). Комната зовёт её не только чтобы
   принять черновик: в принятьЧерновикТихо (server/комнаты.js, функция
   отказЧерновикаДоИгры) она через неё же берёт сохранённый черновик, чтобы
   приложить его к своему отказу (Т2а, Т3). Поэтому мусор и опоздавший
   черновик игра обязана отклонять ДО любой записи в партию — проверки ниже
   стоят раньше записи нарочно. Переставь их местами — и отказ комнаты молча
   станет приёмом: черновик ляжет в партию, хотя игроку ответили «нет». */
function принятьЧерновик(партия, место, черновик) {
  if (!партия || !Array.isArray(партия.игроки) || партия.игроки.indexOf(место) === -1) return отказ('Партия недоступна');
  if (партия.завершена) return ответЧерновика(партия, место, 'Партия уже окончена');
  if (!черновик || typeof черновик !== 'object' || Array.isArray(черновик)) return ответЧерновика(партия, место, 'Черновик не читается');
  /* У черновика поля «действие» не бывает. Есть — это ход другой двери
     (или подделка вроде «сдаться» с приказами): в черновики его не берём. */
  if ('действие' in черновик) return ответЧерновика(партия, место, 'Черновик не читается');
  /* Свою сверку раунда держим здесь, а не только у комнаты: дверь не должна
     зависеть от того, позвал ли кто-то устаревшийХод до неё. */
  const опоздал = устаревшийХод(партия, место, черновик);
  if (опоздал) return Object.assign(опоздал, { черновик: копияЧерновика(партия.черновики[место]) });
  // Выбывшее и сдавшееся место черновиков не шлёт: иначе комната засчитала бы ход.
  if (!вИгре(партия, место)) return ответЧерновика(партия, место, 'Вы уже не в игре');
  if (партия.готовКто[место]) return ответЧерновика(партия, место, 'Сначала нажмите „Изменить“');
  if (!номераОбластейПросты(черновик)) return ответЧерновика(партия, место, 'Черновик не читается');
  const чистый = чистыйЧерновик(черновик);
  let проверка;
  try {
    проверка = П.проверитьЧерновик(партия, место, чистый);
  } catch (e) {
    return ответЧерновика(партия, место, понятнаяПричина(e, 'захват'));
  }
  if (!проверка.принято) return ответЧерновика(партия, место, проверка.причина);
  партия.черновики[место] = копияЧерновика(чистый);
  return ответЧерновика(партия, место, null);
}

/* ---------------------------------------------------------------------
   И3, И4. Кто ещё не нажал «Готово». Кончилась партия — ждать некого.
   --------------------------------------------------------------------- */
function неГотовы(партия) {
  if (!партия || партия.завершена || !Array.isArray(партия.игроки)) return [];
  return партия.игроки.filter(function (место) {
    return вИгре(партия, место) && !партия.готовКто[место];
  });
}

function всеГотовы(партия) {
  return !!партия && !партия.завершена && неГотовы(партия).length === 0;
}

/* ---------------------------------------------------------------------
   И14. Бот составляет черновик и жмёт «Готово» одним ходом. Место уже
   готово, вне игры или партия кончилась — null.
   --------------------------------------------------------------------- */
/* Черновик бота. Упал бот — место всё равно закрывается, как у молчащего
   человека: пустой черновик, остаток подкрепления по 3.3. Иначе комната
   ждала бы хода, которого не будет, и раунд не разобрался бы никогда. */
function черновикБота(партия, место, уровень) {
  try {
    return Б.решить(партия, место, уровеньБота(уровень), случай);
  } catch (e) {
    console.error('захват: бот не смог составить черновик, место закрыто пустым', e);
    return П.пустойЧерновик();
  }
}

function ходЗаБота(партия, место, уровень) {
  if (!партия || партия.завершена || !вИгре(партия, место) || партия.готовКто[место]) return null;
  const черновик = черновикБота(партия, место, уровень);
  партия.черновики[место] = П.остатокПоПросрочке(партия, место, черновик);
  партия.готовКто[место] = 'бот';
  return { событие: 'готово', ктоСделал: место };
}

/* ---------------------------------------------------------------------
   И5 (минимально, нужен уже здесь: без разбора партия не дойдёт до конца).
   Разбор раунда по черновикам; открывает следующий раунд и сбрасывает ✓.
   Конец партии записывают сами правила — одним местом (закончить, 15.2).
   Когда разбирать (все готовы, срок, 8 секунд раскрытия) — решает комната.
   --------------------------------------------------------------------- */
function разобратьРаунд(партия) {
  if (!партия || партия.завершена) return отказ('Партия уже окончена');
  /* Хозяева до разбора открыты всем (их показывала карта весь раунд). Снимок
     нужен браузеру, вернувшемуся посреди раскрытия: прошлого вида у него нет,
     а раскрытие строится из карты «до» и «после». Только хозяева — ни
     черновиков, ни войск сюда не кладём. */
  const хозяеваДо = партия.хозяева.slice();
  // Войска на начало раунда — те же, что показывала карта; расстановки (черновики) в них нет.
  const войскаДо = партия.войска.slice();
  /* «До победы»: десять минут считаем по часам сервера от начала первого
     раунда — сон и уход из игры их не останавливают. Правила проверят время
     после раунда (причина «время»), поэтому счётчик обновляем до разбора. */
  if (партия.доПобеды) партия.потраченоМс = сейчас() - началоПартии(партия);
  let разбор;
  try {
    разбор = П.разобратьРаунд(партия, партия.черновики, случай);
  } catch (e) {
    return отказ(понятнаяПричина(e, 'захват'));
  }
  перенестиСостояние(партия, разбор.партия);
  партия.разобранВ = сейчас();
  партия.готовКто = {};
  партия.ботГотовВ = {};
  партия.события = разбор.события;
  партия.раундСобытий = разбор.раунд;
  партия.хозяеваДоРазбора = хозяеваДо;
  партия.войскаДоРазбора = войскаДо;
  return { принято: true, событие: 'раунд' };
}

/* ---------------------------------------------------------------------
   Время (ТЗ 3.6). Все миги — миллисекунды по часам сервера.
   --------------------------------------------------------------------- */
const МС_В_СЕКУНДЕ = 1000;

function былРазбор(партия) {
  return typeof партия.разобранВ === 'number';
}

/* Конец раскрытия прошлого раунда; в первом раунде раскрытия не было —
   берём начало партии. Нет метки начала (например, партия поднята из
   памяти) — ставим её при первом обращении, как домино: иначе отсчёт шёл
   бы от «сейчас» при каждом вызове, и первый раунд не кончился бы никогда. */
function конецРаскрытия(партия) {
  if (былРазбор(партия)) return партия.разобранВ + П.ЧИСЛА.раскрытиеСекунд * МС_В_СЕКУНДЕ;
  if (typeof партия.началась !== 'number') партия.началась = сейчас();
  return партия.началась;
}

/* И6. Раньше этого разбирать нельзя: у кого-то ещё идёт раскрытие прошлого
   раунда. В первом раунде предела нет — 0. */
function мсДоРазбора(партия) {
  if (!партия || !былРазбор(партия)) return 0;
  return Math.max(0, партия.разобранВ + П.ЧИСЛА.разборНеРаньшеСекунд * МС_В_СЕКУНДЕ - сейчас());
}

/* И13. Секунды до срока раунда (комната сама переводит в мс). Срок:
   прошлый разбор + раскрытие + время раунда; в первом раунде — начало
   партии + время раунда + прибавка первому раунду, без раскрытия. */
function остатокВремениНаХод(партия) {
  if (!партия || партия.завершена) return Infinity;
  const секунд = партия.секундНаРаунд || П.ЧИСЛА.секундНаРаунд.обычно;
  const срок = былРазбор(партия)
    ? конецРаскрытия(партия) + секунд * МС_В_СЕКУНДЕ
    : конецРаскрытия(партия) + (секунд + П.ЧИСЛА.прибавкаПервомуРаундуСекунд) * МС_В_СЕКУНДЕ;
  return Math.max(0, (срок - сейчас()) / МС_В_СЕКУНДЕ);
}

/* Уровень бота за место от комнаты: null — место водит человек. Нет
   функции — считаем, что ботов нет (людям черновик идёт как есть). */
function спроситьУровень(уровеньМеста, место) {
  if (typeof уровеньМеста !== 'function') return null;
  const уровень = уровеньМеста(место);
  return уровень === null || уровень === undefined ? null : уровень;
}

function пустойЛиЧерновик(черновик) {
  if (!черновик) return true;
  const расстановка = черновик.расстановка || {};
  const приказы = черновик.приказы || [];
  return Object.keys(расстановка).length === 0 && приказы.length === 0;
}

/* ---------------------------------------------------------------------
   И7. Время вышло: закрываем ВСЕХ не готовых разом и разбираем раунд.
   Людям — их черновик как есть с остатком по 3.3; за ботом, который ещё
   не составил черновик, бот составляет его сейчас (упал бот — пустой
   черновик, см. черновикБота). Черновики сперва собираем в сторонке и
   пишем в партию, только когда все собраны: упадут правила на середине —
   партия не останется закрытой наполовину.

   До срока не разбираем: будильник комнаты зовёт сюда и раньше времени.
   Небольшой допуск — как у домино и деберца: будильник может сработать
   на миллисекунду раньше срока, а второго комната уже не заведёт.
   --------------------------------------------------------------------- */
const ДОПУСК_ПРОСРОЧКИ_МС = 50;

function ходПоПросрочке(партия, уровеньМеста) {
  if (!партия || партия.завершена || !Array.isArray(партия.игроки)) return null;
  if (остатокВремениНаХод(партия) * МС_В_СЕКУНДЕ > ДОПУСК_ПРОСРОЧКИ_МС) return null;
  const новые = {};
  try {
    неГотовы(партия).forEach(function (место) {
      const уровень = спроситьУровень(уровеньМеста, место);
      let черновик = партия.черновики[место];
      if (уровень !== null && пустойЛиЧерновик(черновик)) черновик = черновикБота(партия, место, уровень);
      новые[место] = П.остатокПоПросрочке(партия, место, черновик);
    });
  } catch (e) {
    console.error('захват: ход по просрочке не собрал черновики', e);
    return null;
  }
  Object.keys(новые).forEach(function (место) { партия.черновики[место] = новые[место]; });
  const разбор = разобратьРаунд(партия);
  if (!разбор.принято) {
    console.error('захват: разбор по просрочке не удался — ' + разбор.причина);
    return null;
  }
  return разбор;
}

/* ---------------------------------------------------------------------
   И8. Ходы ботов без очереди.

   ктоСходит: среди не готовых мест, которые водит бот, — то, чей миг
   раньше всех. Миг назначается ОДИН раз за раунд, при первой встрече
   места, и лежит в партии (ботГотовВ): таймер бота у комнаты один и
   перезаводится на каждой перемене за столом, а миг от этого не едет.
   Разбор раунда ботГотовВ сбрасывает — в новом раунде миги новые.
   --------------------------------------------------------------------- */
function назначитьМиг(партия, место, уровень) {
  const задержкаМс = Math.round(Б.задержкаСекунд(уровеньБота(уровень), случай) * МС_В_СЕКУНДЕ);
  партия.ботГотовВ[место] = Math.max(сейчас(), конецРаскрытия(партия)) + задержкаМс;
}

/* При равных мигах раньше ходит меньший номер места. */
function порядокМеста(партия, место) {
  return номерМеста(место) || партия.игроки.indexOf(место) + 1;
}

function ктоСходит(партия, уровеньМеста) {
  if (!партия || партия.завершена || !Array.isArray(партия.игроки)) return null;
  if (!партия.ботГотовВ) партия.ботГотовВ = {};
  let лучший = null;
  неГотовы(партия).forEach(function (место) {
    const уровень = спроситьУровень(уровеньМеста, место);
    if (уровень === null) return;
    if (typeof партия.ботГотовВ[место] !== 'number') назначитьМиг(партия, место, уровень);
    const миг = партия.ботГотовВ[место];
    const раньше = !лучший || миг < лучший.миг ||
      (миг === лучший.миг && порядокМеста(партия, место) < порядокМеста(партия, лучший.кто));
    if (раньше) лучший = { кто: место, карта: уровень, миг: миг };
  });
  if (!лучший) return null;
  return { кто: лучший.кто, карта: лучший.карта, пауза: Math.max(0, лучший.миг - сейчас()) };
}

/* сходить: тот же ход, что ходЗаБота (И14). Мига у места нет — значит,
   план составлен в прошлом раунде (разбор миги сбросил): такой план
   устарел, ход не делаем. */
function сходить(партия, кто, карта) {
  if (!партия || партия.завершена || !партия.ботГотовВ || typeof партия.ботГотовВ[кто] !== 'number') return null;
  return ходЗаБота(партия, кто, карта);
}

/* ---------------------------------------------------------------------
   И9. Место ушло из комнаты (ТЗ 3.8–3.9): дальше его водит бот, а в местах
   итога оно — как выбывшее в раунде ухода. Раунд ухода, счётчик уходов,
   «люди» и конец партии ведут правила (П.уйти) — одним местом с браузером.
   Здесь — только то, чего правила не знают: что делать с черновиком.
   --------------------------------------------------------------------- */
function местоУшло(партия, место) {
  if (!партия || !Array.isArray(партия.игроки) || партия.игроки.indexOf(место) === -1) return отказ('Партия недоступна');
  if (партия.завершена) return отказ('Партия уже окончена');
  /* У места, уже вне игры (выбыло или сдалось), правила раунд ухода и
     счётчик не пишут — только убирают его из людей. */
  const ответ = П.уйти(партия, место);
  if (!ответ.принято) {
    /* Место ушло уже раньше (вызов пришёл второй раз) — менять нечего,
       только убедиться, что его нет среди людей. Черновик и ✓ не трогаем:
       правило ниже — только для первого, принятого ухода. */
    партия.люди = (партия.люди || []).filter(function (к) { return к !== место; });
    return отказ(ответ.причина);
  }
  /* Черновик — по тому, кто нажал «Готово» (3.9 п.2); решаем только после
     того, как правила приняли уход. Нажал сам или бот за спящего — черновик
     и ✓ остаются и играют. Не нажал никто — черновик выбрасываем, а старый
     миг бота забываем: бот назначит новый (ТЗ 11.3: позже из «миг ухода» и
     «конец раскрытия» плюс задержка) и составит свой черновик. */
  const нажал = партия.готовКто[место];
  if (нажал !== 'сам' && нажал !== 'бот') {
    delete партия.готовКто[место];
    партия.черновики[место] = П.пустойЧерновик();
    if (партия.ботГотовВ) delete партия.ботГотовВ[место];
  }
  return { принято: true, причина: null, завершена: !!партия.завершена };
}

/* ---------------------------------------------------------------------
   И10. Человек снова за местом: вернулся за стол или проснулся (3.9, 11.3).
   Пометку ушедшего снимают и в «люди» возвращают правила; счётчик уходов
   остаётся — по нему виден повторный уход. ✓ бота снимаем: дальше решает
   человек, а черновик бота становится его черновиком. Свой ✓ остаётся.
   Миг бота забываем — иначе бот нажал бы «Готово» за вернувшегося.
   --------------------------------------------------------------------- */
function местоСноваЧеловек(партия, место) {
  if (!партия || !Array.isArray(партия.игроки) || партия.игроки.indexOf(место) === -1) return отказ('Партия недоступна');
  if (партия.завершена) return отказ('Партия уже окончена');
  const ответ = П.вернуться(партия, место);
  if (!ответ.принято) return отказ(ответ.причина);
  if (партия.готовКто[место] === 'бот') delete партия.готовКто[место];
  if (партия.ботГотовВ) delete партия.ботГотовВ[место];
  return { принято: true, причина: null };
}

/* Рассказ о событии словами. «Готово» и «Изменить» — без слов: меняется
   только ✓ в полосе (ТЗ 15.2). Имя не склоняем — «Аня сдаётся» без рода. */
function текстСобытия(событие, ктоЯ) {
  if (!событие || событие.что !== 'сдался') return '';
  if (событие.кто === ктоЯ) return 'Вы сдались';
  return (событие.имя || 'Игрок') + ' сдаётся';
}

/* =====================================================================
   И16. ВИД ДЛЯ ИГРОКА (ТЗ 15.3) — собирается вручную, поле за полем.

   Тайна приказов: свой черновик видит только его хозяин; у остальных — лишь
   ✓ готовности. Чужие черновики, черновики ботов, миги ботов (ботГотовВ),
   кто нажал «Готово» (готовКто) и случай наружу не уходят никогда.
   Внутренние ключи мест («бот-3») наружу не уходят: в блоке «захват» вместо
   ключа — номер места за столом (номерМеста), тот же, что в «я» и в
   игроки[].номер. Цвет места — его порядок в партии (как цветХозяина в
   js/захват-карта-вид.js).
   ===================================================================== */

/* Номер места вместо внутреннего ключа. Чужой ключ (не из этой партии) —
   null: лучше пустое поле, чем утечка внутреннего имени. */
function номерДляВида(партия, ключ) {
  const и = партия.игроки.indexOf(ключ);
  if (и === -1) return null;
  return номерМеста(ключ) || и + 1;
}

/* Копия публичных данных (события раунда, итог) с ключами мест, заменёнными
   на номера, — замечание ревью А8 п.4. События и итог правил открыты всем
   по замыслу (раскрытие показывает всё), тайны в них нет; но ключей мест в
   них много (кто, у, прошла, колонны[].кто, места[].кто, победители), и
   перечислять поля по видам событий значит однажды пропустить новое. Поэтому
   любая строка, равная ключу места, становится номером. */
function безКлючей(партия, значение) {
  if (Array.isArray(значение)) return значение.map(function (з) { return безКлючей(партия, з); });
  if (значение && typeof значение === 'object') {
    const копия = {};
    Object.keys(значение).forEach(function (поле) {
      const имяПоля = партия.игроки.indexOf(поле) !== -1 ? String(номерДляВида(партия, поле)) : поле;
      копия[имяПоля] = безКлючей(партия, значение[поле]);
    });
    return копия;
  }
  if (typeof значение === 'string' && партия.игроки.indexOf(значение) !== -1) return номерДляВида(партия, значение);
  return значение;
}

/* Строка места из списка комнаты (списокМест): имя, бот, спит. */
function строкаКомнаты(обёртка, ключ) {
  const список = Array.isArray(обёртка.участники) ? обёртка.участники
    : Array.isArray(обёртка.места) ? обёртка.места : [];
  return список.find(function (м) { return м && м.ключ === ключ; }) || null;
}

function областейУ(партия, ключ) {
  return партия.хозяева.filter(function (х, н) { return н > 0 && х === ключ; }).length;
}

/* Полоса игроков (15.3): всё, что видят все. «Ушёл» и «сдался» — из партии,
   «этоБот» и «спит» — из списка мест комнаты. */
function игрокиДляВида(партия, обёртка) {
  const ушли = партия.ушлоВРаунде || {};
  const выбыли = партия.выбыли || {};
  const сдались = партия.сдались || {};
  return партия.игроки.map(function (к, порядок) {
    const строка = строкаКомнаты(обёртка, к);
    const номер = номерДляВида(партия, к);
    return {
      номер: номер,
      имя: строка && строка.имя ? String(строка.имя) : 'Игрок ' + номер,
      цвет: порядок,
      областей: областейУ(партия, к),
      очков: П.очки(партия, к),
      подкрепление: партия.подкрепление[к] || 0,
      готов: !!партия.готовКто[к],
      выбыл: !!выбыли[к],
      ушёл: typeof ушли[к] === 'number',
      сдался: !!сдались[к],
      // Не «бот»: так зовут внутренний ключ места за столом на двоих.
      этоБот: !!(строка && строка.этоБот),
      спит: !!(строка && строка.спит === true)
    };
  });
}

/* Подкрепление этому игроку (3.2): всего — то, что примет проверка
   черновика, и разбивка для подсказки. */
function моёПодкрепление(партия, место) {
  const разбивка = П.подкрепление(партия, место);
  return {
    всего: партия.подкрепление[место] || 0,
    заОбласти: разбивка.заОбласти,
    края: разбивка.края.map(function (к) { return { название: к.название, прибавка: к.прибавка }; }),
    заСтолицы: разбивка.заСтолицы
  };
}

/* Свой черновик — только своему месту. Составил его бот (спящему, 11.3) —
   с пометкой, чтобы человек знал, чьи это приказы. */
function мойЧерновик(партия, место) {
  const черновик = партия.черновики[место] || П.пустойЧерновик();
  const расстановка = {};
  Object.keys(черновик.расстановка || {}).forEach(function (область) {
    расстановка[область] = черновик.расстановка[область];
  });
  return {
    расстановка: расстановка,
    приказы: (черновик.приказы || []).map(function (п) { return { из: п.из, в: п.в, сколько: п.сколько }; }),
    составилБот: партия.готовКто[место] === 'бот'
  };
}

/* Миллисекунды до конца раунда (3.6); партия окончена — таймера нет. */
function мсДоКонца(партия) {
  if (партия.завершена) return null;
  const секунд = остатокВремениНаХод(партия);
  return Number.isFinite(секунд) ? Math.round(секунд * МС_В_СЕКУНДЕ) : null;
}

/* Начало партии по часам сервера; нет метки (партия поднята из памяти) —
   ставим её сейчас, как в конецРаскрытия. */
function началоПартии(партия) {
  if (typeof партия.началась !== 'number') партия.началась = сейчас();
  return партия.началась;
}

/* Сколько мс осталось до конца партии «До победы». Считаем от часов сервера,
   в партию не пишем. У обычного стола и у оконченной партии — null. */
function мсДоКонцаПартии(партия) {
  if (!партия.доПобеды || партия.завершена) return null;
  const копия = { доПобеды: true, потраченоМс: сейчас() - началоПартии(партия) };
  return Math.max(0, П.мсДоКонцаПартии(копия));
}

/* Хозяева областей номерами мест (ничья область — null). */
function хозяеваНомерами(партия, хозяева) {
  return хозяева.map(function (х) { return х === null ? null : номерДляВида(партия, х); });
}

/* Отмену (3.9) пишет комната, не игра: партия завершена, а «результат» не
   строка (server/комнаты.js — ветка «партия отменена» в выйти и
   стеретьИтогПартии при общем обрыве). У обычного конца результат — всегда
   строка (15.2). Сам результат — ключ места — наружу не отдаём, только «да/нет». */
function партияОтменена(партия) {
  return typeof партия.результат !== 'string';
}

function блокЗахвата(партия, место, обёртка) {
  const захват = {
    карта: партия.карта,
    раунд: партия.раунд,
    всегоРаундов: партия.всегоРаундов,
    мсДоКонца: мсДоКонца(партия),
    мсДоКонцаПартии: мсДоКонцаПартии(партия),
    // Полная длина раунда (3.6) — для полоски времени; мсДоКонца — сколько осталось.
    секундНаРаунд: партия.секундНаРаунд || П.ЧИСЛА.секундНаРаунд.обычно,
    хозяева: хозяеваНомерами(партия, партия.хозяева),
    войска: партия.войска.slice(),
    столицы: партия.столицы.map(function (с) {
      return { область: с.область, хозяинНаСтарте: номерДляВида(партия, с.хозяинНаСтарте) };
    }),
    игроки: игрокиДляВида(партия, обёртка),
    я: номерДляВида(партия, место),
    моёПодкрепление: моёПодкрепление(партия, место),
    мойЧерновик: мойЧерновик(партия, место),
    яГотов: !!партия.готовКто[место],
    события: безКлючей(партия, Array.isArray(партия.события) ? партия.события : []),
    раундСобытий: typeof партия.раундСобытий === 'number' ? партия.раундСобытий : null
  };
  /* Карта до разбора — вместе с событиями того же разбора: по ним браузер
     строит раскрытие. В первом раунде разбора не было — поля нет. */
  if (захват.раундСобытий !== null && Array.isArray(партия.хозяеваДоРазбора)) {
    захват.хозяеваДо = хозяеваНомерами(партия, партия.хозяеваДоРазбора);
    // Войска «до» — только числа в том же порядке областей (после перезагрузки поля может не быть).
    if (Array.isArray(партия.войскаДоРазбора)) захват.войскаДо = партия.войскаДоРазбора.slice();
  }
  // «До победы» (5а): только признак, без пределов и счёта.
  захват.доПобеды = партия.доПобеды === true;
  if (партия.завершена) захват.отменена = партияОтменена(партия);
  if (партия.завершена && партия.итог) захват.итог = безКлючей(партия, партия.итог);
  return захват;
}

/* ---------------------------------------------------------------------
   Знак внимания — как у домино (server/игры/домино.js): из сырой записи
   комнаты (обёртка.знакСырой) — только номер, имя и признаки; «от» и «кому»
   — порядок мест в партии (по нему общая панель ищет фишку).

   Фраза одному (ТЗ 6, 15.3, 15.4 «Фразы одному»): знак с целью, который не
   бросок, видят только адресат и сказавший. Остальным — как будто фразы не
   было: прежний общий знак, если он ещё виден, или ничего. Прежний общий
   знак помнит комната и сама решает, виден ли он ещё (обёртка.знакОбщийСырой,
   по часам комнаты): своих часов и памяти для знаков у игры нет. Бросок с
   целью видят все — он летит через стол.
   --------------------------------------------------------------------- */
function фразаОдному(сырой) {
  return !!сырой.цель && !З.этоБросок(сырой.номер);
}

function собратьЗнак(партия, место, сырой) {
  return {
    номер: сырой.номер,
    порядковый: Number(сырой.порядковый) || 0,
    имя: String(сырой.имя || ''),
    этоЯ: сырой.кто === место,
    цель: String(сырой.имяЦели || ''),
    вМеня: !!сырой.цель && сырой.цель === место,
    от: партия.игроки.indexOf(сырой.кто),
    кому: партия.игроки.indexOf(сырой.цель)
  };
}

/* общийСырой — прежний общий знак от комнаты; протухший комната не отдаёт.
   Берём его, только если он и правда общий и старше фразы. */
function знакДляВида(партия, место, сырой, общийСырой) {
  if (!сырой || !З.этоЗнак(сырой.номер)) return null;
  if (!фразаОдному(сырой)) return собратьЗнак(партия, место, сырой);
  if (место === сырой.кто || место === сырой.цель) return собратьЗнак(партия, место, сырой);
  const виден = !!общийСырой && З.этоЗнак(общийСырой.номер) && !фразаОдному(общийСырой) &&
    (Number(общийСырой.порядковый) || 0) < (Number(сырой.порядковый) || 0);
  return виден ? собратьЗнак(партия, место, общийСырой) : null;
}

/* Общие поля комнаты на компанию (прихожая) — как у домино и монополии. */
function полосаКомнаты(вид, место, обёртка) {
  Object.assign(вид, {
    мест: обёртка.мест, мойНомер: обёртка.мойНомер, яХозяин: !!обёртка.яХозяин,
    можноНачать: !!обёртка.можноНачать, парами: false, уровеньБотов: обёртка.уровеньБотов
  });
  вид.застолом = обёртка.места.map(function (м) {
    const строка = {
      номер: номерМеста(м.ключ), имя: м.имя, этоЯ: м.ключ === место, этоБот: !!м.этоБот,
      хозяин: !!м.хозяин, наСвязи: !!м.наСвязи, ушёл: !!м.ушёл, хочетЕщё: !!м.хочетЕщё, напарник: null
    };
    // Пометка «спит» — только у спящего и только «да», как у домино.
    if (м.спит === true) строка.спит = true;
    return строка;
  });
}

function видДляИгрока(партия, место, обёртка = {}) {
  const вид = {
    игра: 'захват', код: обёртка.код, этап: обёртка.этап, версия: обёртка.версия,
    номерСобытия: обёртка.номерСобытия, событие: обёртка.событие || '', сыграноПартий: обёртка.сыграноПартий,
    яХочуЕщё: !!обёртка.яХочуЕщё, соперникХочетЕщё: !!обёртка.соперникХочетЕщё,
    соперникПришёл: !!обёртка.соперникПришёл, соперникНаСвязи: !!обёртка.соперникНаСвязи,
    соперникУшёл: !!обёртка.соперникУшёл, имяСоперника: String(обёртка.имяСоперника || 'Соперник'),
    завершена: !!(партия && партия.завершена), яХожу: false,
    // По этим признакам общая панель показывает «Сказать» и броски.
    знакиВниманияЕсть: true, броскиЕсть: true
  };
  /* Длина партии для строки прихожей («Захват · 20 раундов» / «до победы»):
     общий перенос полей обёртки этот вид не касается — собираем вручную,
     только значение из списка правил, чужое не пропускаем. */
  if (П.ЧИСЛА.раундов.варианты.includes(обёртка.раундовЗахвата)) вид.раундовЗахвата = обёртка.раундовЗахвата;
  if (Array.isArray(обёртка.места)) полосаКомнаты(вид, место, обёртка);
  if (партия && Array.isArray(партия.игроки) && партия.игроки.indexOf(место) !== -1) {
    вид.захват = блокЗахвата(партия, место, обёртка);
    const знак = знакДляВида(партия, место, обёртка.знакСырой, обёртка.знакОбщийСырой);
    if (знак) вид.знакВнимания = знак;
  }
  return вид;
}

