function раздать(_, настройки) {
  const игроки = (настройки?.игроки || []).slice();
  if (![2, 3, 4].includes(игроки.length) || new Set(игроки).size !== игроки.length) throw Error('Нужно от двух до четырёх разных игроков');
  if (настройки?.парами && игроки.length !== 4) throw Error('Для 2 на 2 нужны четыре игрока');
  return { игроки, парами: !!настройки?.парами, игра: П.создать(Math.random, настройки?.цельДеберца ?? 301, true,
    настройки?.парами ? '2x2' : String(игроки.length)), завершена: false, результат: null, проигравшие: [] };
}
function чейХод(п) { return п && !п.завершена ? п.игроки[п.игра.ход] : null; }
function сделатьХод(п, кто, намерение) {
  const игрок = п?.игроки.indexOf(кто);
  if (!п || игрок < 0) return { принято: false, причина: 'Вас нет за этим столом' };
  if (п.завершена) return { принято: false, причина: 'Партия уже закончена' };
  const и = п.игра, действие = намерение?.действие;
  if (действие === 'сдаться') {
    П.сдаться(и, игрок);
  } else {
    if (чейХод(п) !== кто) return { принято: false, причина: 'Сейчас не ваш ход' };
    try {
      if (действие === 'торг') П.торг(и, игрок, намерение.масть);
      else if (действие === 'карта') П.сыграть(и, игрок, намерение.id);
      else if (действие === 'взятка') П.забрать(и);
      else if (действие === 'раздача') {
        if (и.фаза === 'итог' && и.версияПравил < 6) { и.версияПравил = 6; и.следующийСдающий = (и.сдающий + 1) % и.руки.length; }
        П.раздать(и);
      }
      else return { принято: false, причина: 'Неизвестное действие' };
    } catch (ошибка) { return { принято: false, причина: ошибка.message }; }
  }
  if (и.фаза === 'конец') {
    const победители = и.победители?.length ? и.победители : [и.победитель];
    п.завершена = true; п.результат = п.игроки[победители[0]];
    п.проигравшие = п.игроки.filter((_, i) => !победители.includes(i));
  }
  return { принято: true, событие: действие };
}
function ходЗаБота(п, кто, уровень) {
  if (чейХод(п) !== кто) return null;
  const и = п.игра, игрок = п.игроки.indexOf(кто);
  let ход;
  if (и.фаза === 'торговля') ход = { действие: 'торг', масть: Б.козырь(и.руки[игрок], П.вариантыКозыря(и), уровень) ?? (П.обязанВыбрать(и) ? П.вариантыКозыря(и)[0] : null) };
  else if (и.фаза === 'игра') {
    const лидер = П.старшаяКарта(и);
    ход = { действие: 'карта', id: Б.карта(П.доступные(и, игрок), лидер?.карта, и.козырь, уровень, и.сыграно,
      Math.random, !!лидер && и.парами && лидер.игрок % 2 === игрок % 2).id };
  }
  else ход = { действие: и.фаза === 'взятка' ? 'взятка' : 'раздача' };
  return сделатьХод(п, кто, ход).принято ? { событие: ход.действие, ктоСделал: кто } : null;
}
const карта = к => к ? { id: к.id, масть: к.масть, имя: к.имя } : null;
function видДляИгрока(п, кто, добавка = {}) {
  // Никаких spread исходного состояния: чужая рука и запас никогда
  // не сериализуются. Числа игроков в виде всегда относительно получателя.
  const вид = { игра: 'деберц', код: добавка.код, этап: добавка.этап,
    версия: добавка.версия, номерСобытия: добавка.номерСобытия, событие: добавка.событие || '',
    сыграноПартий: добавка.сыграноПартий, яХочуЕщё: !!добавка.яХочуЕщё,
    соперникХочетЕщё: !!добавка.соперникХочетЕщё, соперникПришёл: !!добавка.соперникПришёл,
    соперникНаСвязи: !!добавка.соперникНаСвязи, соперникУшёл: !!добавка.соперникУшёл,
    имяСоперника: typeof добавка.имяСоперника === 'string' ? добавка.имяСоперника : 'Друг',
    завершена: !!п?.завершена, яХожу: false, знакиВниманияЕсть: true, броскиЕсть: true };
  const знак = добавка.знакСырой;
  if (знак && З.этоЗнак(знак.номер)) вид.знакВнимания = {
    номер: знак.номер, порядковый: Number(знак.порядковый) || 0, имя: String(знак.имя || ''), этоЯ: знак.кто === кто,
    цель: String(знак.имяЦели || ''), вМеня: знак.цель === кто,
    от: п?.игроки ? (п.игроки.indexOf(знак.кто) - п.игроки.indexOf(кто) + п.игроки.length) % п.игроки.length : 0,
    кому: п?.игроки && знак.цель ? (п.игроки.indexOf(знак.цель) - п.игроки.indexOf(кто) + п.игроки.length) % п.игроки.length : null
  };
  if (Array.isArray(добавка.места)) {
    вид.мест = добавка.мест; вид.мойНомер = добавка.мойНомер;
    вид.яХозяин = !!добавка.яХозяин; вид.можноНачать = !!добавка.можноНачать;
    вид.парами = !!добавка.парами; вид.уровеньБотов = добавка.уровеньБотов;
    вид.застолом = добавка.места.map(м => ({ номер: номерМеста(м.ключ), имя: м.имя,
      этоЯ: м.ключ === кто, этоБот: !!м.этоБот, хозяин: !!м.хозяин, наСвязи: !!м.наСвязи,
      ушёл: !!м.ушёл, хочетЕщё: !!м.хочетЕщё,
      напарник: вид.парами ? (номерМеста(м.ключ) + 1) % 4 + 1 : null }));
  }
  if (!п) return вид;
  const я = п.игроки.indexOf(кто);
  if (я < 0) return вид;
  const и = п.игра, n = п.игроки.length;
  const порядок = Array.from({ length: n }, (_, i) => (я + i) % n);
  const пара = значения => порядок.map(i => значения[i]);
  const счёт = значения => и.парами ? [значения[я % 2], значения[1 - я % 2]] : пара(значения);
  const место = i => i == null ? null : (i - я + n) % n;
  const имена = порядок.map(i => добавка.места?.find(м => м.ключ === п.игроки[i])?.имя || (i === я ? 'Вы' : n === 2 ? вид.имяСоперника : 'Игрок ' + (i + 1)));
  const победители = п.завершена && п.результат != null ? п.игроки.map((_, i) => i).filter(i => !п.проигравшие.includes(п.игроки[i])).map(место) : [];
  вид.яХожу = чейХод(п) === кто;
  вид.деберц = {
    режим: и.режим || '2', мест: n, парами: !!и.парами, имена, местаИгроков: порядок.map(i => номерМеста(п.игроки[i])),
    количестваКарт: пара(и.руки.map(р => р.length)), победители, ничья: п.завершена && п.результат == null,
    цель: и.цель || 301,
    объявления: пара((и.объявления || [[], []]).map(список => список.map(к => ({
      название: к.название, очки: к.очки, масть: к.масть, верх: к.верх
    })))),
    белаОбъявлена: пара(и.белаОбъявлена || [false, false]),
    белаСтатус: пара(и.белаСтатус || и.руки.map(() => null)),
    белла: порядок.map(i => i === я && !!и.белла[i]),
    фаза: п.завершена ? 'конец' : и.фаза, номер: и.номер, ход: место(и.ход), сдающий: место(и.сдающий),
    версияПравил: и.версияПравил, круг: и.круг, козырь: и.козырь, заказчик: место(и.заказчик), открытая: карта(и.открытая), фреза: карта(и.фреза),
    рука: и.руки[я].map(карта), картУСоперника: и.руки[порядок[1]].length,
    стол: и.стол.map(к => ({ игрок: место(к.игрок), карта: карта(к.карта) })),
    счёт: счёт(и.счёт), очки: пара(и.очки), взятки: пара(и.взятки), бонусы: пара(и.бонусы), висят: и.висят,
    историяРаздач: (и.историяРаздач || []).map(р => ({ номер: р.номер, запись: счёт(р.запись), счёт: счёт(р.счёт) })),
    можно: П.доступные(и, я).map(к => к.id),
    победитель: победители.length ? и.парами ? (победители.includes(0) ? 0 : 1) : победители[0] : null,
    итог: и.итог ? { описание: и.итог.описание, сырые: счёт(и.итог.сырые), запись: счёт(и.итог.запись) }
      : п.завершена ? { описание: 'Партия закончена', сырые: и.счёт.map(() => 0), запись: и.счёт.map(() => 0) } : null,
    последняяВзятка: и.последняяВзятка ? {
      победитель: место(и.последняяВзятка.победитель),
      карты: и.последняяВзятка.карты.map(к => ({ игрок: место(к.игрок), карта: карта(к.карта) }))
    } : null
  };
  return вид;
}
