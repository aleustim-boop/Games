'use strict';
const П = require('../../js/домино-правила');
const Б = require('../../js/домино-бот');
const З = require('../../js/деберц-знаки');
const { номерМеста } = require('../партия-по-сети');
/* Обычная Error из правил (throw Error('текст')) уже по-русски — показываем
   как есть. Техническую ошибку JS (TypeError, RangeError, ReferenceError,
   SyntaxError, а то и не Error вовсе) игрок не видит, даже если в тексте
   случайно есть кириллица (утечка вида «Cannot read ... 'флоты'»); такую
   ошибку со стеком пишем в журнал, обычный отказ правил — не пишем, иначе
   журнал забьётся частыми отказами и потеряется настоящий сбой. */
function понятнаяПричина(e, где) { if (e instanceof Error && e.constructor === Error) return e.message; console.error(где + ': сбой хода', e); return 'Такой ход не принят'; }

/* Время на ход (этап 11а, решение владельца 30.09). За большим столом один
   задумавшийся держит всех остальных, поэтому от трёх мест на ход даётся
   минута; не успел — ход за него делает тот же бот, что водит ушедших, но
   игрок остаётся за столом и следующий свой ход делает сам. На двоих часов
   нет: там ждут только одного человека, и так было всегда.
   Секунды считает не правило (js/домино-правила.js часов не знает), а этот
   модуль по меткам сейчас(); будильник заводит комната по остатку. */
const СЕКУНД_НА_ХОД = 60;
const МЕСТ_ДЛЯ_ЧАСОВ = 3;
/* Будильник комнаты может сработать на миллисекунду раньше срока. Без
   допуска ходПоПросрочке ответил бы «ещё не пора», а второго будильника
   комната уже не заведёт — стол встал бы навсегда (тот же шрам у шахмат). */
const ДОПУСК_ПРОСРОЧКИ_МС = 50;
/* Уровень бота, который ходит за просрочившего: разумный ход без случайности,
   чтобы не наказывать человека нарочно плохой костью. */
const УРОВЕНЬ_ЗА_ПРОСРОЧИВШЕГО = 'обычный';
let срокНаХодСекунд = СЕКУНД_НА_ХОД;

/* Единственный источник времени. Проверка подменяет module.exports.сейчас,
   чтобы двигать время без ожидания. */
function сейчас() { return module.exports.сейчас(); }

/* Только для проверок: короткий срок вместо минуты. Без довода — вернуть
   настоящий. Отдаёт прежний срок, чтобы проверка могла его восстановить. */
function подменитьСрокНаХодДляПроверки(секунд) {
  const прежний = срокНаХодСекунд;
  срокНаХодСекунд = Number.isFinite(секунд) && секунд >= 0 ? секунд : СЕКУНД_НА_ХОД;
  return прежний;
}

function естьЧасы(п) { return !!п && !п.завершена && п.игроки.length >= МЕСТ_ДЛЯ_ЧАСОВ; }

/* Метка «с этого мгновения ходит новый человек». Пока очередь у того же
   места (взял из базара и ещё кладёт), метку не трогаем: минута даётся
   на весь ход, а не на каждое нажатие. */
function отметкаОчереди(п) { return чейХод(п) + '|' + п.игра.раунд + '|' + п.игра.фаза; }

function раздать(_, настройки = {}) {
  const игроки = (настройки.игроки || []).slice();
  if (![2, 3, 4].includes(игроки.length) || new Set(игроки).size !== игроки.length) throw Error('Нужно от двух до четырёх игроков');
  return { игроки, хозяин: игроки.includes(настройки.хозяин) ? настройки.хозяин : игроки[0], игра: П.создать(игроки.length, настройки.цельДомино || 100), завершена: false, результат: null, проигравшие: [], началоХода: сейчас() };
}
function чейХод(п) { return !п || п.завершена ? null : п.игра.фаза === 'итог' ? п.хозяин : п.игроки[п.игра.ход] || null; }
/* Для комнаты (пометка «спит»): стоит итог раунда — очередь у хозяина, но это
   не ход. Пропуск итога сна не зарабатывает, а за спящего хозяина бот
   «раунд» не жмёт — итог ждёт обычный срок (см. server/комнаты.js). */
function наИтогеРаунда(п) { return !!п && !п.завершена && п.игра.фаза === 'итог'; }
function сделатьХод(п, кто, н = {}) {
  const i = п?.игроки.indexOf(кто);
  if (!п || i < 0 || п.завершена) return { принято: false, причина: 'Партия недоступна' };
  const очередьДо = отметкаОчереди(п);
  try {
    if (!н || typeof н !== 'object') throw Error('Ход не разобран');
    if (н.действие === 'раунд') {
      if (кто !== п.хозяин) throw Error('Следующий раунд начинает хозяин стола');
      П.следующий(п.игра);
    } else П.действие(п.игра, i, н);
  } catch (e) { return { принято: false, причина: понятнаяПричина(e, 'домино') }; }
  if (п.игра.фаза === 'конец') {
    п.завершена = true; п.результат = п.игроки[п.игра.победители[0]];
    п.проигравшие = п.игроки.filter((_, index) => !п.игра.победители.includes(index));
  }
  if (отметкаОчереди(п) !== очередьДо) п.началоХода = сейчас();
  return { принято: true, событие: н.действие };
}
function ходЗаБота(п, кто, уровень) {
  if (чейХод(п) !== кто) return null;
  const move = п.игра.фаза === 'итог' ? { действие: 'раунд' } : Б.ход(П.вид(п.игра, п.игроки.indexOf(кто)), уровень);
  return move && сделатьХод(п, кто, move).принято ? { событие: move.действие, ктоСделал: кто } : null;
}

/** Для будильника комнаты: сколько СЕКУНД осталось ходящему; нет часов — Infinity. */
function остатокВремениНаХод(п) {
  if (!естьЧасы(п) || !чейХод(п)) return Infinity;
  const прошлоСекунд = (сейчас() - (п.началоХода || сейчас())) / 1000;
  return Math.max(0, срокНаХодСекунд - прошлоСекунд);
}

/* Ход за просрочившего доводим до конца: бот, которому нечем ходить,
   сперва берёт из базара, а очередь при этом остаётся у того же места.
   Остановись мы на добыче — просрочивший получил бы ещё целую минуту
   на ту же очередь. Больше двух шагов (базар, потом кость или пас) не
   бывает; третий — запас, чтобы цикл не мог стать вечным. */
function доделатьХодЗаПросрочившего(п, кто) {
  let последний = null;
  for (let шаг = 0; шаг < 3 && чейХод(п) === кто; шаг++) {
    const сделано = ходЗаБота(п, кто, УРОВЕНЬ_ЗА_ПРОСРОЧИВШЕГО);
    if (!сделано) break;
    последний = сделано;
    if (сделано.событие !== 'базар') break;
  }
  return последний;
}

/**
 * Время на ход вышло: ход за игрока делает бот, партия идёт дальше.
 * Игрока НЕ помечаем ни ушедшим, ни сдавшимся — пометки живут в комнате,
 * а здесь только законный ход по правилам. Наружу — лишь то, что и так
 * видно всем за столом (какое действие и чьё); рука остаётся в партии.
 */
function ходПоПросрочке(п) {
  if (!естьЧасы(п)) return null;
  const кто = чейХод(п);
  if (!кто || остатокВремениНаХод(п) * 1000 > ДОПУСК_ПРОСРОЧКИ_МС) return null;
  const наИтоге = п.игра.фаза === 'итог';
  const сделано = доделатьХодЗаПросрочившего(п, кто);
  // Запоминаем, что это был не ход, а «раунд начался сам»: слова для стола другие (см. видДляИгрока).
  if (сделано) п.просрочкаНаИтоге = наИтоге;
  return сделано ? { событие: сделано.событие, ктоСделал: кто } : null;
}
/* Рассказ о событии комнаты словами. Пока рассказываем только про ход по
   времени: остальные ходы видны по столу, и слов не просят. Имя не склоняем
   («Время Аня вышло» читается плохо) — ставим его перед двоеточием, как
   у шахмат; «ход сделал бот» без рода. */
function текстСобытия(событие, ктоЯ) {
  if (!событие || событие.что !== 'ход-по-времени') return '';
  if (событие.кто === ктоЯ) return 'Время вышло — ход за вас сделал бот';
  return (событие.имя || 'Игрок') + ': время вышло — ход сделал бот';
}

function видДляИгрока(п, кто, d = {}) {
  const v = { игра: 'домино', код: d.код, этап: d.этап, версия: d.версия, номерСобытия: d.номерСобытия,
    событие: d.событие || '', сыграноПартий: d.сыграноПартий, яХочуЕщё: !!d.яХочуЕщё, соперникХочетЕщё: !!d.соперникХочетЕщё,
    соперникПришёл: !!d.соперникПришёл, соперникНаСвязи: !!d.соперникНаСвязи, соперникУшёл: !!d.соперникУшёл,
    имяСоперника: String(d.имяСоперника || 'Соперник'), завершена: !!п?.завершена, яХожу: чейХод(п) === кто,
    знакиВниманияЕсть: true, броскиЕсть: true };
  if (Array.isArray(d.места)) {
    v.мест = d.мест; v.мойНомер = d.мойНомер; v.яХозяин = !!d.яХозяин; v.можноНачать = !!d.можноНачать; v.парами = false; v.уровеньБотов = d.уровеньБотов;
    v.застолом = d.места.map(m => {
      const место = { номер: номерМеста(m.ключ), имя: m.имя, этоЯ: m.ключ === кто, этоБот: !!m.этоБот, хозяин: !!m.хозяин, наСвязи: !!m.наСвязи, ушёл: !!m.ушёл, хочетЕщё: !!m.хочетЕщё, напарник: null };
      /* Пометка «спит» (server/комнаты.js, усыпить): место водит бот, но это
         человек. Ключ — только у спящего и только «да»: без спящих ответ прежний. */
      if (m.спит === true) место.спит = true;
      return место;
    });
  }
  if (п && п.игроки.includes(кто)) {
    const я = п.игроки.indexOf(кто); v.домино = П.вид(п.игра, я);
    v.домино.имена = п.игроки.map((key, i) => d.места?.find(m => m.ключ === key)?.имя || (i === я ? 'Вы' : п.игроки.length === 2 ? v.имяСоперника : `Игрок ${i + 1}`));
    v.домино.местаИгроков = п.игроки.map(номерМеста);
    v.домино.можноПродолжить = кто === п.хозяин;
    /* Секунды до просрочки хода — тем же именем и в том же виде, что у дурака
       (см. server/партия-по-сети.js): округлены вверх, «часов нет» — null.
       Общий сборщик вида домино не зовёт (у игры свой видДляИгрока), поэтому
       без этой строки экран о сроке ничего бы не узнал. Решает по-прежнему
       сервер (ходПоПросрочке); экран только рисует число. */
    const остаток = остатокВремениНаХод(п);
    v.остатокСекундНаХод = Number.isFinite(остаток) ? Math.ceil(остаток) : null;
    /* Слова про время для подсказки: признак виду события собираем вручную —
       экран по нему, а не по тексту, отличает просрочку от голосования и ухода.
       «ход-по-времени» — ход за игрока сделал бот; «раунд-сам» — на итоге раунда
       хозяин не нажал, и раунд начался сам (всем одинаковые слова). */
    if (d.событиеСырое && d.событиеСырое.что === 'ход-по-времени') {
      if (п.просрочкаНаИтоге) { v.видСобытия = 'раунд-сам'; v.событие = 'Следующий раунд начался сам'; }
      else v.видСобытия = 'ход-по-времени';   // слова уже собрала комната для этого игрока (текстСобытия ниже по цепочке)
    }
    if (п.завершена && п.игра.фаза !== 'конец') { v.домино.фаза = 'конец'; v.домино.прерван = true; v.домино.победители = []; }
    const z = d.знакСырой;
    if (z && З.этоЗнак(z.номер)) v.знакВнимания = { номер: z.номер, порядковый: Number(z.порядковый) || 0, имя: String(z.имя || ''), этоЯ: z.кто === кто, цель: String(z.имяЦели || ''), вМеня: z.цель === кто, от: п.игроки.indexOf(z.кто), кому: п.игроки.indexOf(z.цель) };
  }
  return v;
}
