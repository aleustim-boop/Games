function раздать(_, настройки = {}) {
  const игроки = (настройки.игроки || []).slice();
  if (![2, 3, 4].includes(игроки.length) || new Set(игроки).size !== игроки.length) throw Error('Нужно от двух до четырёх игроков');
  return { игроки, хозяин: игроки.includes(настройки.хозяин) ? настройки.хозяин : игроки[0], игра: П.создать(игроки.length, настройки.цельДомино || 100), завершена: false, результат: null, проигравшие: [] };
}
function чейХод(п) { return !п || п.завершена ? null : п.игра.фаза === 'итог' ? п.хозяин : п.игроки[п.игра.ход] || null; }
function сделатьХод(п, кто, н = {}) {
  const i = п?.игроки.indexOf(кто);
  if (!п || i < 0 || п.завершена) return { принято: false, причина: 'Партия недоступна' };
  try {
    if (н.действие === 'раунд') {
      if (кто !== п.хозяин) throw Error('Следующий раунд начинает хозяин стола');
      П.следующий(п.игра);
    } else П.действие(п.игра, i, н);
  } catch (e) { return { принято: false, причина: e.message }; }
  if (п.игра.фаза === 'конец') {
    п.завершена = true; п.результат = п.игроки[п.игра.победители[0]];
    п.проигравшие = п.игроки.filter((_, index) => !п.игра.победители.includes(index));
  }
  return { принято: true, событие: н.действие };
}
function ходЗаБота(п, кто, уровень) {
  if (чейХод(п) !== кто) return null;
  const move = п.игра.фаза === 'итог' ? { действие: 'раунд' } : Б.ход(П.вид(п.игра, п.игроки.indexOf(кто)), уровень);
  return move && сделатьХод(п, кто, move).принято ? { событие: move.действие, ктоСделал: кто } : null;
}
function видДляИгрока(п, кто, d = {}) {
  const v = { игра: 'домино', код: d.код, этап: d.этап, версия: d.версия, номерСобытия: d.номерСобытия,
    событие: d.событие || '', сыграноПартий: d.сыграноПартий, яХочуЕщё: !!d.яХочуЕщё, соперникХочетЕщё: !!d.соперникХочетЕщё,
    соперникПришёл: !!d.соперникПришёл, соперникНаСвязи: !!d.соперникНаСвязи, соперникУшёл: !!d.соперникУшёл,
    имяСоперника: String(d.имяСоперника || 'Соперник'), завершена: !!п?.завершена, яХожу: чейХод(п) === кто,
    знакиВниманияЕсть: true, броскиЕсть: true };
  if (Array.isArray(d.места)) {
    v.мест = d.мест; v.мойНомер = d.мойНомер; v.яХозяин = !!d.яХозяин; v.можноНачать = !!d.можноНачать; v.парами = false; v.уровеньБотов = d.уровеньБотов;
    v.застолом = d.места.map(m => ({ номер: номерМеста(m.ключ), имя: m.имя, этоЯ: m.ключ === кто, этоБот: !!m.этоБот, хозяин: !!m.хозяин, наСвязи: !!m.наСвязи, ушёл: !!m.ушёл, хочетЕщё: !!m.хочетЕщё, напарник: null }));
  }
  if (п && п.игроки.includes(кто)) {
    const я = п.игроки.indexOf(кто); v.домино = П.вид(п.игра, я);
    v.домино.имена = п.игроки.map((key, i) => d.места?.find(m => m.ключ === key)?.имя || (i === я ? 'Вы' : п.игроки.length === 2 ? v.имяСоперника : `Игрок ${i + 1}`));
    v.домино.местаИгроков = п.игроки.map(номерМеста);
    v.домино.можноПродолжить = кто === п.хозяин;
    if (п.завершена && п.игра.фаза !== 'конец') { v.домино.фаза = 'конец'; v.домино.прерван = true; v.домино.победители = []; }
    const z = d.знакСырой;
    if (z && З.этоЗнак(z.номер)) v.знакВнимания = { номер: z.номер, порядковый: Number(z.порядковый) || 0, имя: String(z.имя || ''), этоЯ: z.кто === кто, цель: String(z.имяЦели || ''), вМеня: z.цель === кто, от: п.игроки.indexOf(z.кто), кому: п.игроки.indexOf(z.цель) };
  }
  return v;
}
