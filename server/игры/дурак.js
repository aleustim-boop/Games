'use strict';

/* =====================================================================
   ДУРАК ДЛЯ СЕРВЕРА — обёртка вокруг server/партия-по-сети.js.

   Зачем она нужна. Игр на сервере стало две, и комната (server/комнаты.js)
   не должна знать, какая из них лежит на столе: сегодня она зовёт правила
   дурака по именам, и каждое такое имя — гвоздь, которым вторая игра
   прибита к первой. Здесь эти имена собраны в одном месте и переведены
   на общий язык — договор «игра для сервера» (см. server/игры/реестр.js).

   Своих правил в этом файле НЕТ ни строчки. Он только пересказывает
   вопросы комнаты той самой партии по сети, что работала до сих пор:
   раздача, чей ход, вид для игрока, ход, ход за бота, знаки внимания.
   Поэтому дурак от появления обёртки не меняется ничем — и это главное
   требование к шагу, на котором она написана.

   ВАЖНОЕ ПРАВИЛО ЭТОГО ФАЙЛА: все обращения идут ЧЕРЕЗ объект «партии»
   (партии.видДляИгрока(...)), а не через вытащенные заранее ссылки
   (const вид = партии.видДляИгрока). Разница не косметическая. Проверки
   ловят утечку чужих карт тем, что подменяют «видДляИгрока» прямо в
   объекте партии на сыщика. Вытащи мы ссылку при загрузке — подмена
   промахнулась бы мимо цели, и сыщик молча пропускал бы всё, оставаясь
   зелёным. Сторож, который перестал сторожить, хуже отсутствующего.
   ===================================================================== */

const партии = require('../партия-по-сети.js');

module.exports = {
  /* Как эта игра называется в запросах и ответах. Слово то же, что игра
     присылает в «/создать» и что страница кладёт в window.ИграСтраницы. */
  имя: 'дурак',

  /** Сколько мест бывает за столом и бывают ли пары. */
  мест: {
    мин: партии.МИН_ИГРОКОВ,
    макс: партии.МАКС_ИГРОКОВ,
    впарах: партии.ИГРОКОВ_В_ПАРАХ
  },

  /** Раздать карты и начать партию. Настройки стола собирает комната. */
  раздать: function (ктоНачинает, настройки) {
    return партии.начатьПартию(ктоНачинает, настройки);
  },

  /** Чей сейчас ход — внутреннее имя места или null. */
  чейХод: function (партия) {
    return партии.чейХод(партия);
  },

  /**
   * Что видит этот игрок. Единственная дверь наружу: всё, что уходит
   * человеку, собирается там вручную поле за полем.
   */
  видДляИгрока: function (партия, ктоЯ, добавка) {
    return партии.видДляИгрока(партия, ктоЯ, добавка);
  },

  /** Ход человека. Правила проверяет игра, а не страница. */
  сделатьХод: function (партия, ктоЯ, намерение) {
    return партии.сделатьХод(партия, ктоЯ, намерение);
  },

  /** Ход бота — теми же правилами, что и ход человека. */
  ходЗаБота: function (партия, место, уровень) {
    return партии.ходЗаБота(партия, место, уровень);
  },

  /** Сколько бот «думает» перед ходом: обычным и тем, что вне очереди. */
  темпБота: {
    обычный: партии.ПАУЗА_БОТА,
    внеОчереди: партии.ПАУЗА_БОТА_НА_ПОДХВАТ
  },

  /**
   * Ход вне очереди — у дурака это подхват: бот бросает заходную карту,
   * когда очередь не его. Игра, где такого не бывает (шашки), кладёт
   * сюда null, и комната про подхват даже не спрашивает.
   */
  ходВнеОчереди: {
    ктоСходит: function (партия, уровень) {
      return партии.ктоИзБотовПодхватит(партия, уровень);
    },
    сходить: function (партия, кто, карта) {
      return партии.подхватЗаБота(партия, кто, карта);
    }
  },

  /** Кто кому напарник за собранным столом. Без пар — всегда null. */
  напарник: function (занятые, место) {
    return партии.напарникЗаСтолом(занятые, место);
  },

  /** Знаки внимания: смайлики, фразы и броски с адресатом. */
  знаки: {
    сколько: function () { return партии.сколькоЗнаковВнимания(); },
    этоЗнак: function (номер) { return партии.этоЗнакВнимания(номер); },
    этоБросок: function (номер) { return партии.этоБросок(номер); },
    голосБота: function (сделано) { return партии.знакБота(сделано); }
  },

  /**
   * Рассказ о том, что случилось за столом, — словами для человека.
   * Это ещё полуфабрикат: видДляИгрока перепишет его богаче, с картами
   * и числами, а сырое поле выбросит.
   */
  текстСобытия: function (событие, ктоЯ, места, этоКомпания, подробности) {
    return партии.текстСобытия(событие, ктоЯ, места, этоКомпания, подробности);
  }
};
