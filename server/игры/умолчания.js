'use strict';

/* =====================================================================
   УМОЛЧАНИЯ ИГР — один список на весь сервер.

   ЗАЧЕМ. Слово «дурак» как игра-по-умолчанию и веса партий были
   переписаны отдельно в трёх файлах: рейтинге, силе игроков и
   статистике. Пока игр было две, это никого не смущало. Стало больше —
   и каждую новую приходится вспоминать вписать руками в несколько мест.
   Забудем одну — рейтинг новой игры молча не заведётся, и заметит это
   владелец, а не мы.

   ЧТО ЗДЕСЬ ЕСТЬ:

     ПО_УМОЛЧАНИЮ — игра, которой считается запрос без имени игры.
       Старые страницы и старые ссылки поля «игра» не присылают вовсе,
       и для них ничего не должно меняться. Отсюда «дурак».

     ИГРЫ — что сервер знает про каждую игру. Пока это одно число: вес
       партии для силы игроков. Оно не выдумано, а замерено (подробности
       у самого числа в server/сила-игроков.js): в дураке многое решают
       карты, поэтому одна партия говорит о силе вчетверо меньше, чем
       партия в шашки.

     ВЕС_НЕЗНАКОМОЙ — как считать игру, которой в списке нет. Осторожно,
       по дураку: ошибиться в меньшую сторону дешевле, чем объявить
       человека сильным по одной случайной партии.

   ЧЕГО ЗДЕСЬ НЕТ НАРОЧНО. Списка «какие игры вообще бывают» тут нет,
   и заводить его не надо. Рейтинг и статистика устроены так, что новая
   игра заводится сама: рейтинг открывает ей таблицу по первому же имени,
   статистика — счётчик с двоеточием. Это правильно: сервер не должен
   мешать появлению игры, о которой он ещё не слышал. Список игр, в
   которые МОЖНО ИГРАТЬ ПО СЕТИ, — это другое, и он живёт отдельно
   (server/игры/реестр.js): там за именем стоят настоящие правила.
   ===================================================================== */

/* Игра, которой считается запрос без имени. */
const ПО_УМОЛЧАНИЮ = 'дурак';

/* Что сервер знает про игры. Новая игра добавляется одной строкой сюда —
   и её узнают все трое: рейтинг, сила игроков и статистика. */
const ИГРЫ = {
  дурак:    { вес: 0.3 },
  шашки:    { вес: 1 },
  шахматы:  { вес: 1 },
  нарды:    { вес: 0.3 }
};

/* Вес партии в игре, которой нет в списке. */
const ВЕС_НЕЗНАКОМОЙ = 0.3;

/**
 * Привести имя игры к рабочему виду: пусто и мусор — игра по умолчанию.
 * Одно место на весь сервер: раньше эта строчка была переписана в трёх
 * файлах, и в четвёртый её просто забыли бы добавить.
 */
function имяИгры(игра) {
  return typeof игра === 'string' && игра ? игра : ПО_УМОЛЧАНИЮ;
}

/**
 * Вес партии для силы игроков. Незнакомая игра считается осторожно,
 * по дураку, — см. пояснение в шапке.
 */
function весИгры(игра) {
  const запись = ИГРЫ[имяИгры(игра)];
  return запись && typeof запись.вес === 'number' ? запись.вес : ВЕС_НЕЗНАКОМОЙ;
}

/** Считается ли эта игра в общих счётчиках статистики (без двоеточия). */
function этоИграПоУмолчанию(игра) {
  return имяИгры(игра) === ПО_УМОЛЧАНИЮ;
}

/** Имена игр, про которые сервер что-то знает, — для проверок и сводок. */
function известныеИгры() {
  return Object.keys(ИГРЫ);
}

module.exports = {
  ПО_УМОЛЧАНИЮ: ПО_УМОЛЧАНИЮ,
  ВЕС_НЕЗНАКОМОЙ: ВЕС_НЕЗНАКОМОЙ,
  имяИгры: имяИгры,
  весИгры: весИгры,
  этоИграПоУмолчанию: этоИграПоУмолчанию,
  известныеИгры: известныеИгры
};
