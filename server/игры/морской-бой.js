function раздать(первый, настройки = {}) {
  const игроки = (настройки.игроки || []).slice(0, 2);
  return { игроки, завершена: false, результат: null, проигравшие: [], игра: П.создать(игроки.includes(первый) ? игроки.indexOf(первый) : Math.random() < .5 ? 0 : 1) };
}
function чейХод(п) {
  if (!п || п.завершена) return null;
  return п.игроки[п.игра.фаза === 'расстановка' ? п.игра.готовы.indexOf(false) : п.игра.ход] || null;
}
function сделатьХод(п, кто, н = {}) {
  const i = п?.игроки.indexOf(кто);
  if (!п || i < 0 || п.завершена) return { принято: false, причина: 'Партия недоступна' };
  try {
    if (н.действие === 'готов') П.готов(п.игра, i, н.флот);
    else if (н.действие === 'выстрел') П.стрелять(п.игра, i, н.клетка);
    else if (н.действие === 'сдаться') П.сдаться(п.игра, i);
    else return { принято: false, причина: 'Неизвестное действие' };
  } catch (e) { return { принято: false, причина: e.message }; }
  if (п.игра.фаза === 'конец') { п.завершена = true; п.результат = п.игроки[п.игра.победитель]; п.проигравшие = п.игроки.filter(x => x !== п.результат); }
  return { принято: true, событие: н.действие };
}
function ходЗаБота(п, кто, уровень) {
  const i = п.игроки.indexOf(кто);
  if (i < 0) return null;
  const н = п.игра.фаза === 'расстановка' ? { действие: 'готов', флот: П.случайныйФлот() }
    : { действие: 'выстрел', клетка: Б.выстрел(П.вид(п.игра, i).вашиВыстрелы, уровень) };
  return сделатьХод(п, кто, н).принято ? { событие: н.действие, ктоСделал: кто } : null;
}
function видДляИгрока(п, кто, d = {}) {
  const v = { игра: 'морской-бой', код: d.код, этап: d.этап, версия: d.версия, номерСобытия: d.номерСобытия,
    событие: d.событие || '', сыграноПартий: d.сыграноПартий, яХочуЕщё: !!d.яХочуЕщё, соперникХочетЕщё: !!d.соперникХочетЕщё,
    соперникПришёл: !!d.соперникПришёл, соперникНаСвязи: !!d.соперникНаСвязи, соперникУшёл: !!d.соперникУшёл,
    имяСоперника: String(d.имяСоперника || 'Соперник'), завершена: !!п?.завершена, яХожу: чейХод(п) === кто,
    знакиВниманияЕсть: true, броскиЕсть: true };
  if (п && п.игроки.includes(кто)) {
    const я = п.игроки.indexOf(кто);
    v.море = П.вид(п.завершена && п.игра.фаза !== 'конец' ? { ...п.игра, фаза: 'конец', победитель: -1 } : п.игра, я);
    v.море.прерван = п.завершена && п.результат == null;
    v.море.местоСоперника = номерМеста(п.игроки[1 - я]);
  }
  const z = d.знакСырой;
  if (z && З.этоЗнак(z.номер)) v.знакВнимания = { номер: z.номер, порядковый: Number(z.порядковый) || 0, имя: String(z.имя || ''), этоЯ: z.кто === кто, цель: String(z.имяЦели || ''), вМеня: z.цель === кто, от: z.кто === кто ? 0 : 1, кому: z.цель === кто ? 0 : 1 };
  return v;
}
