'use strict';

/* =====================================================================
   НАРДЫ ДЛЯ СЕРВЕРА — третья игра, которую комната кладёт на стол.

   Своих правил здесь нет ни строчки: расстановка, кубики, перемещения,
   бой, вынос, марс и кокс берутся из js/нарды-правила.js — того же
   файла, что читает браузер. Так же устроены дурак и шашки: правила не
   раздваиваются, иначе сервер и экран однажды разойдутся в решениях,
   и такую ошибку будут искать неделю.

   ЧТО ЗДЕСЬ ЕСТЬ. Перевод с языка комнаты («место за столом», «ход
   игрока», «вид для игрока») на язык нард («цвет», «бросок», «доска»)
   и обратно. Договор, по которому комната разговаривает с игрой,
   описан в server/игры/реестр.js.

   ТРИ ДЕЙСТВИЯ ОДНОЙ ДВЕРИ «/ход»:

     { действие: 'бросить' }                          — кубики бросает СЕРВЕР;
     { действие: 'ход', шаги: [{откуда,куда,кубик}] } — ход ЦЕЛИКОМ;
     { действие: 'сдаться' }                          — партия кончена.

   Пустой список шагов — это законный пропуск: бросок бывает таким, что
   ходить нечем вовсе. Пропуск при живых шагах не принимается.

   ПОЧЕМУ ХОД ПРИХОДИТ ЦЕЛИКОМ. Правила умеют принимать только доигранный
   ход: недоигранный «сделатьХод» отвергает и доску не трогает. Приди ход
   по одному перемещению — серверу пришлось бы хранить полуход и уметь его
   откатывать, а на дубле это четыре обращения и четыре рассылки вместо
   одной. Плата за целый ход одна: соперник не видит, как вы двигаете
   шашки, пока не подтвердите. Она уже принята в шашках.

   «КЛИЕНТУ НЕ ВЕРИМ» — здесь это главное правило файла:

     * кубики от браузера не принимаются ВОВСЕ: числа бросает сервер
       (функция «кость» ниже) и отдаёт их правилам;
     * ход — только список «откуда-куда», и каждое перемещение
       переспрашивается у правил («Правила.сделатьХод»); не сошлось —
       доска не тронута, а игроку уходит отказ словами;
     * наружу партия целиком не уходит никогда: вид собирается вручную,
       поле за полем (см. «видДляИгрока»). Внутренние имена мест
       («человек», «бот-3») не покидают этот файл.

   ЦВЕТА ПО МЕСТАМ. Белые — тот, кого комната назвала начинающим (на
   реванше это проигравший прошлой партии), второй за столом — чёрные.
   Первый ход в нардах всегда за белыми: розыгрыша первого броска у нас
   нет, как нет его и в игре против бота на телефоне.
   ===================================================================== */

const Правила = require('../../js/нарды-правила.js');
const Бот = require('../../js/нарды-бот.js');

/* За доской ровно двое, и пар не бывает. */
const МЕСТ_ЗА_ДОСКОЙ = 2;

/* Сколько бот «думает» перед ходом. Пауза нужна человеку: ход, который
   случается мгновенно, глазом не поймать. У нард она чуть длиннее, чем
   у шашек: за один ход уезжает до четырёх шашек сразу. */
const ПАУЗА_БОТА = 900;

/* Сколько бот думает НА СЕРВЕРЕ. В браузере потолок 300 мс, и там это
   правильно: стол один. На сервере столов много, а счёт идёт синхронно —
   эти 300 мс тормозят разом всех, кто в эту секунду ходит. Половина
   бюджета сохраняет разницу между уровнями и не держит чужие столы. */
const БЮДЖЕТ_НА_СЕРВЕРЕ = 150;

/* Уровни у нард свои ('лёгкий', 'сложный', 'мастер'), а комната умеет
   давать дураковы ('лёгкий', 'обычный', 'сложный'). Незнакомое слово —
   не повод падать: играем средним, как делают шашки. */
const УРОВЕНЬ_ПО_УМОЛЧАНИЮ = 'сложный';

const ГРАНЕЙ_У_КУБИКА = 6;

/* Больше четырёх перемещений не бывает даже на дубле. Отсекаем длинный
   список сразу: разбирать сотню «перемещений» от кого-то любопытного
   правилам незачем. */
const МАКСИМУМ_ПЕРЕМЕЩЕНИЙ = 4;

/* Бросок одной кости. Это не правило нард, а случайность, и живёт она
   на сервере нарочно: числа, присланные браузером, не принимаются. */
function кость() { return 1 + Math.floor(Math.random() * ГРАНЕЙ_У_КУБИКА); }

/**
 * Раздать — то есть расставить шашки и назначить цвета.
 *
 * Партия наружу выглядит одинаково у всех игр сервера: комната смотрит
 * в неё четырьмя полями — «игроки», «завершена», «результат»,
 * «проигравшие», — и они здесь есть. Остальное читает только этот файл.
 *
 * настройки.вариантНард — 'короткие' или 'длинные'. Поля нет или слово
 * незнакомое — короткие: это то, во что играют чаще, и то, что стоит
 * первым в лобби.
 */
function раздать(ктоНачинает, настройки) {
  const н = настройки || {};
  const все = (Array.isArray(н.игроки) ? н.игроки : []).slice(0, МЕСТ_ЗА_ДОСКОЙ);
  const белые = все.indexOf(ктоНачинает) !== -1 ? ктоНачинает : все[0];
  const чёрные = все.filter(function (место) { return место !== белые; })[0] || null;

  const цвета = {};
  if (белые) цвета[белые] = Правила.БЕЛЫЕ;
  if (чёрные) цвета[чёрные] = Правила.ЧЁРНЫЕ;

  const вариант = н.вариантНард === Правила.ДЛИННЫЕ ? Правила.ДЛИННЫЕ : Правила.КОРОТКИЕ;

  return {
    игроки: все,
    завершена: false,
    результат: null,
    проигравшие: [],
    /* Ничьей в нардах не бывает вовсе — ни по правилам, ни по соглашению.
       Поле всё равно есть: комната спрашивает его у любой игры. */
    ничья: false,
    цвета: цвета,
    доска: Правила.создатьПартию({ вид: вариант, первый: Правила.БЕЛЫЕ }),
    /* Последний ход целиком, со всеми перемещениями по порядку. Без них
       чужой ход выглядит телепортацией: было четыре шашки на месте, стало
       четыре в другом, а какая куда поехала — не видно. */
    последнийХод: null,
    /* Чем кончилась партия. Правила знают только свои концы (вынос, марс,
       кокс); сдача — конец стола, а не правил, и пишется сюда же, чтобы
       вид для игрока собирался из одного места. */
    цена: 0,
    видПобеды: null,
    причинаКонца: null
  };
}

/** Место, которое играет этим цветом. */
function местоЦвета(партия, цвет) {
  for (const место of партия.игроки) {
    if (партия.цвета[место] === цвет) return место;
  }
  return null;
}

/** Цвет соперника. Слова берём у правил, чтобы они были одни и те же. */
function другойЦвет(цвет) {
  return цвет === Правила.БЕЛЫЕ ? Правила.ЧЁРНЫЕ : Правила.БЕЛЫЕ;
}

/** Чей сейчас ход — внутреннее имя места или null, если партия кончилась. */
function чейХод(партия) {
  if (!партия || партия.завершена) return null;
  return местоЦвета(партия, Правила.чейХод(партия.доска));
}

/**
 * Записать итог в саму партию: комната читает его этими же полями
 * у любой игры (см. «учестьИтогПартии» и «выйти» в server/комнаты.js).
 */
function записатьИтог(партия) {
  if (!Правила.партияЗавершена(партия.доска)) return;
  const итог = Правила.итог(партия.доска);
  const победитель = местоЦвета(партия, итог.победитель);
  партия.завершена = true;
  партия.результат = победитель;
  партия.проигравшие = партия.игроки.filter(function (место) { return место !== победитель; });
  партия.ничья = false;
  партия.цена = итог.цена;
  партия.видПобеды = итог.видПобеды;
  партия.причинаКонца = итог.причина;
}

/* =====================================================================
   ДВЕРЬ «/ход»: бросок, ход, сдача
   ===================================================================== */

/**
 * Что игрок хочет сделать. Возвращает { принято: true, событие } либо
 * { принято: false, причина } — причина пишется словами игрока: её
 * показывают на экране как есть.
 */
function сделатьХод(партия, ктоЯ, намерение) {
  if (!партия || партия.завершена) {
    return { принято: false, причина: 'Партия уже закончена' };
  }
  const действие = намерение && typeof намерение.действие === 'string'
    ? намерение.действие : '';

  if (действие === 'сдаться') return сдаться(партия, ктоЯ);
  if (действие === 'бросить') return бросить(партия, ктоЯ);
  if (действие === 'ход') return сыгратьХод(партия, ктоЯ, намерение);

  return { принято: false, причина: 'В нардах так не ходят' };
}

/**
 * Бросить кубики. Числа берёт сервер: присланные браузером не смотрим
 * даже краем глаза — иначе выигрывал бы тот, кто починил себе кубики.
 */
function бросить(партия, ктоЯ) {
  if (!партия.цвета[ктоЯ]) return { принято: false, причина: 'Вас нет за этой доской' };
  if (чейХод(партия) !== ктоЯ) return { принято: false, причина: 'Сейчас не ваш ход' };
  if (Правила.бросокПартии(партия.доска)) {
    return { принято: false, причина: 'Кубики уже брошены — теперь ваш ход' };
  }
  const выпало = Правила.бросить(партия.доска, [кость(), кость()]);
  if (!выпало) return { принято: false, причина: 'Бросать сейчас нельзя' };
  return { принято: true, событие: 'бросок' };
}

/**
 * Сыграть ход целиком. Каждое перемещение переспрашивается у правил;
 * не сошлось хоть одно — доска остаётся нетронутой, а игрок получает
 * отказ словами.
 */
function сыгратьХод(партия, ктоЯ, намерение) {
  const мойЦвет = партия.цвета[ктоЯ];
  if (!мойЦвет) return { принято: false, причина: 'Вас нет за этой доской' };
  if (чейХод(партия) !== ктоЯ) return { принято: false, причина: 'Сейчас не ваш ход' };
  if (!Правила.бросокПартии(партия.доска)) {
    return { принято: false, причина: 'Сначала бросьте кубики' };
  }

  const шаги = очиститьШаги(намерение.шаги);
  if (!шаги) {
    return { принято: false, причина: 'Ход не понят: нужен список перемещений «откуда-куда»' };
  }

  /* Вся проверка хода — здесь, в одной строке, и она чужая: правила.
     Своей проверки «а можно ли так» в этом файле нет и быть не должно. */
  const сделанные = Правила.сделатьХод(партия.доска, { шаги: шаги });
  if (!сделанные) {
    return { принято: false, причина: почемуНеВышло(партия.доска, шаги, мойЦвет) };
  }

  партия.последнийХод = {
    /* «кто» — внутреннее имя места, наружу не уходит: вид отдаёт из него
       только признак «мой». Цвет отдаётся — по нему экран решает, чей ход
       проигрывать по шагам. */
    кто: ктоЯ,
    чей: мойЦвет,
    шаги: сделанные.map(копияПеремещения),
    запись: Правила.записьХода({ шаги: сделанные })
  };
  записатьИтог(партия);

  /* Пустой список — это пропуск: бросок выпал такой, что ходить нечем. */
  return { принято: true, событие: сделанные.length ? 'ход' : 'пропуск' };
}

/**
 * Сдаться. Сдаётся тот, кто нажал кнопку, а не тот, чей сейчас ход: по
 * сети это разные вещи — свою кнопку видит только её хозяин. Цена сдачи
 * всегда обычная (1): марс и кокс считаются по вынесенным шашкам, а
 * сдавшийся просто не доиграл.
 */
function сдаться(партия, ктоЯ) {
  const мойЦвет = партия.цвета[ктоЯ];
  if (!мойЦвет) return { принято: false, причина: 'Вас нет за этой доской' };

  партия.завершена = true;
  партия.результат = местоЦвета(партия, другойЦвет(мойЦвет));
  партия.проигравшие = [ктоЯ];
  партия.ничья = false;
  партия.цена = 1;
  партия.видПобеды = 'сдача';
  партия.причинаКонца = (мойЦвет === Правила.БЕЛЫЕ ? 'белые' : 'чёрные') + ' сдались';
  return { принято: true, событие: 'сдался' };
}

/** Копия одного перемещения: чтобы наружу не уехал объект правил. */
function копияПеремещения(ш) {
  return {
    фишка: ш.фишка,
    откуда: ш.откуда,
    куда: ш.куда,
    кубик: ш.кубик,
    побита: ш.побита === undefined ? null : ш.побита,
    вынос: ш.вынос === true
  };
}

/**
 * Разобрать присланные перемещения. Дальше проходит только то, что имеет
 * правильный вид: номер пункта 1…24, слово «бар» в «откуда», слово «вне»
 * в «куда» и, если назван, кубик 1…6. Всё остальное — null, и ход даже
 * не доходит до правил.
 */
function очиститьШаги(сырые) {
  if (!Array.isArray(сырые)) return null;
  if (сырые.length > МАКСИМУМ_ПЕРЕМЕЩЕНИЙ) return null;
  const чистые = [];
  for (const сырой of сырые) {
    if (!сырой || typeof сырой !== 'object') return null;
    const откуда = пунктИлиСлово(сырой.откуда, 'бар');
    const куда = пунктИлиСлово(сырой.куда, 'вне');
    if (откуда === null || куда === null) return null;
    const шаг = { откуда: откуда, куда: куда };
    if (сырой.кубик !== undefined && сырой.кубик !== null) {
      const кубик = Number(сырой.кубик);
      if (!(Number.isInteger(кубик) && кубик >= 1 && кубик <= ГРАНЕЙ_У_КУБИКА)) return null;
      /* Кубик — только уточнение, каким из выпавших играть (при выносе
         годятся два разных). Верим ему не больше, чем всему остальному:
         правила всё равно ищут такое перемещение среди законных. */
      шаг.кубик = кубик;
    }
    чистые.push(шаг);
  }
  return чистые;
}

/** Номер пункта 1…24 или разрешённое здесь особое слово. Иначе null. */
function пунктИлиСлово(значение, особое) {
  if (значение === особое) return особое;
  const номер = Number(значение);
  if (!Number.isInteger(номер) || номер < 1 || номер > Правила.ПУНКТОВ) return null;
  return номер;
}

/**
 * Почему ход не вышел — словами, а не «так нельзя».
 *
 * Разбор идёт по КОПИИ доски и теми же правилами: перемещения делаются
 * по одному, пока одно не откажет, — и объясняем именно его. Своего
 * знания о том, как ходят нарды, здесь нет: все ответы собраны из
 * «возможныеШаги», «пункт» и «наБаре».
 */
function почемуНеВышло(доска, шаги, мойЦвет) {
  if (!шаги.length) return 'Ходить есть чем — пропустить ход нельзя';
  const проба = Правила.копияПартии(доска);
  for (const шаг of шаги) {
    if (Правила.сделатьШаг(проба, шаг)) continue;
    return почемуНеПеремещение(проба, шаг, мойЦвет);
  }
  return 'Ход не доигран: сыграть надо столько кубиков, сколько получается';
}

/** Почему не вышло одно перемещение — в той позиции, где оно споткнулось. */
function почемуНеПеремещение(партия, шаг, мойЦвет) {
  const наБаре = Правила.наБаре(партия, мойЦвет).length;

  /* Обязательный старший кубик берём из снимка правил (картинкаПартии),
     а не читаем внутреннее поле партии напрямую: снимок — то же самое,
     что уходит игроку в вид, и если правила однажды переименуют поле,
     здесь ничего не разъедется. */
  const обязательный = Правила.картинкаПартии(партия).обязательныйКубик;

  if (шаг.откуда === 'бар') {
    if (!наБаре) return 'На баре у вас нет шашек';
    const сБара = Правила.возможныеШаги(партия).filter(function (годный) {
      return String(годный.откуда) === 'бар';
    });
    if (!сБара.length) {
      return обязательный
        ? 'Играть надо старшим кубиком — ' + обязательный + ', с бара так не выйдет'
        : 'С бара сейчас ходить нельзя';
    }
    return 'С бара сюда не зайти — этот пункт занят соперником';
  }
  if (наБаре) return 'Сначала введите шашку с бара — другими ходить нельзя';

  const пункт = Правила.пункт(партия, шаг.откуда);
  if (!пункт.сколько) return 'На этом пункте шашек нет';
  if (пункт.цвет !== мойЦвет) return 'Это шашка соперника — ходить можно только своими';

  const отсюда = Правила.возможныеШаги(партия).filter(function (годный) {
    return String(годный.откуда) === String(шаг.откуда);
  });
  if (!отсюда.length) {
    /* Частая причина «шашка есть, а ходить нельзя» — тот же обязательный
       старший кубик. */
    return обязательный
      ? 'Играть надо старшим кубиком — ' + обязательный + ', этой шашкой так не выйдет'
      : 'Этой шашкой сейчас ходить нельзя';
  }
  return 'Так эта шашка не ходит';
}

