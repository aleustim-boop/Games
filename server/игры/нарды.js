/** Уровень, который понимает бот нард. Незнакомое слово — средний. */
function уровеньБота(уровень) {
  return Бот.УРОВНИ.indexOf(уровень) !== -1 ? уровень : УРОВЕНЬ_ПО_УМОЛЧАНИЮ;
}

/**
 * Ход за бота — теми же правилами и той же дверью, что и ход человека.
 *
 * Думает настоящий бот нард (js/нарды-бот.js), а не серверная его копия:
 * копия — это второй набор решений, который однажды разойдётся с тем,
 * что человек видел в игре против бота на своём телефоне.
 *
 * Бросок и ход делаются за один раз. Разделять их на два вызова нельзя:
 * насос ботов в комнате ждёт от каждого вызова ход, и «бросок без хода»
 * он принял бы за зависание.
 */
function ходЗаБота(партия, место, уровень) {
  if (!партия || партия.завершена) return null;
  if (чейХод(партия) !== место) return null;

  if (!Правила.бросокПартии(партия.доска)) {
    const брошено = сделатьХод(партия, место, { действие: 'бросить' });
    if (!брошено.принято) return null;
  }

  /* Ходить нечем — бот отдаёт пустой список, и это законный пропуск. */
  const задуманный = Бот.выбратьХод(партия.доска, уровеньБота(уровень), БЮДЖЕТ_НА_СЕРВЕРЕ);
  const шаги = задуманный ? задуманный.шаги.map(function (ш) {
    return { откуда: ш.откуда, куда: ш.куда, кубик: ш.кубик };
  }) : [];

  const ответ = сделатьХод(партия, место, { действие: 'ход', шаги: шаги });
  if (!ответ.принято) return null;

  /* Знаков внимания (смайликов и бросков в соперника) у нард пока нет
     вовсе — поэтому боту нечем ни сказать, ни кинуть. */
  return { событие: ответ.событие, ктоСделал: место, эмоция: null, бросок: null };
}

/* =====================================================================
   ЧТО ВИДИТ ИГРОК

   Собираем вручную, поле за полем, — и то, что пришло от комнаты, тоже
   перебираем по одному: служебные полуфабрикаты (сырое событие, сырой
   список мест) наружу уходить не должны. Объект партии целиком не
   отдаётся никогда: доска уходит снимком правил, а внутренние имена
   мест остаются в этом файле.
   ===================================================================== */

function видДляИгрока(партия, ктоЯ, добавка) {
  const пришло = добавка || {};
  const места = Array.isArray(пришло.места) ? пришло.места : [];

  /* Стол на двоих или компания с прихожей — по тому, прислала ли комната
     список мест. Пустого списка быть не должно вовсе: игра на телефоне
     считает любой массив признаком компании и начинает говорить хозяину
     чужие слова (эту беду уже ловили в шашках). */
  const этоКомпания = места.length > 0;

  const вид = {
    игра: 'нарды',
    код: пришло.код,
    этап: пришло.этап,
    версия: пришло.версия,
    номерСобытия: пришло.номерСобытия,
    событие: пришло.событие || '',
    /* Короткое слово события из закрытого набора: «бросок», «ход»,
       «пропуск», «сдался», «вошёл», «ушёл», «пропал». Экран читает
       именно его, а не текст: текст написан для человека и меняется
       вместе со словами игры. Имён и внутренних названий мест в нём нет. */
    видСобытия: пришло.событиеСырое && typeof пришло.событиеСырое.что === 'string'
      ? пришло.событиеСырое.что : '',
    /* Имя того, с кем событие случилось, — ленте оно нужно отдельно от
       текста. Имя то же, что видно за столом: нового наружу не уходит. */
    имяСобытия: пришло.событиеСырое && пришло.событиеСырое.имя
      ? String(пришло.событиеСырое.имя) : '',
    сыграноПартий: пришло.сыграноПартий,
    открытыйСтол: пришло.открытыйСтол === true,
    яХочуЕщё: пришло.яХочуЕщё === true,
    соперникХочетЕщё: пришло.соперникХочетЕщё === true,
    соперникПришёл: пришло.соперникПришёл === true,
    соперникНаСвязи: пришло.соперникНаСвязи === true,
    соперникУшёл: пришло.соперникУшёл === true,
    мест: пришло.мест,
    мойНомер: пришло.мойНомер,
    /* Знаков внимания и бросков в соперника у нард пока нет вовсе —
       говорим об этом прямо, по этим признакам экран решает, показывать
       ли панель смайликов. Мёртвых кнопок не бывает. */
    знакиВниманияЕсть: false,
    броскиЕсть: false,
    застолом: места.map(function (место) {
      return {
        номер: место.номер,
        имя: место.имя,
        этоЯ: место.ключ === ктоЯ,
        этоБот: место.этоБот === true,
        хозяин: место.хозяин === true,
        наСвязи: место.наСвязи !== false,
        ушёл: место.ушёл === true,
        хочетЕщё: место.хочетЕщё === true,
        /* Цвет — единственное, что нарды добавляют к общей плашке места.
           Пока не раздали, цвета ещё нет: он назначается при раздаче. */
        цвет: партия && партия.цвета ? (партия.цвета[место.ключ] || null) : null
      };
    })
  };

  if (этоКомпания) {
    вид.яХозяин = пришло.яХозяин === true;
    вид.можноНачать = пришло.можноНачать === true;
  } else {
    /* Списка мест у стола на двоих быть не должно ВОВСЕ — даже пустого. */
    delete вид.застолом;
  }

  if (!партия) return вид;

  /* Номер кресла соперника. За доской двое, и кресло — это место по
     порядку: внутреннее имя места наружу не отдаём никогда. */
  const соперникЗаДоской = партия.игроки.filter(function (кто) { return кто !== ктоЯ; })[0];
  if (соперникЗаДоской) {
    вид.креслоСоперника = партия.игроки.indexOf(соперникЗаДоской) + 1;
  }

  /* Снимок правил — единственная правда о доске. Из него же берутся
     кубики и счётчики хода: если брать их по отдельности, они однажды
     разойдутся со снимком, и экран нарисует не ту позицию. */
  const снимок = Правила.картинкаПартии(партия.доска);

  вид.вариант = снимок.вид;
  вид.доска = снимок;
  вид.мойЦвет = партия.цвета[ктоЯ] || null;
  вид.чейХод = партия.завершена ? null : снимок.ходит;
  вид.яХожу = чейХод(партия) === ктоЯ;
  /* Что выпало сейчас ([3,5] или [4,4]) и что из этого ещё не сыграно.
     У законченной партии это последний бросок — он так и остаётся
     на столе, как настоящие кубики после победы. */
  вид.бросок = снимок.бросок;
  вид.кубикиОсталось = снимок.кубики;
  вид.максимумКубиков = снимок.максимумКубиков;
  вид.обязательныйКубик = снимок.обязательныйКубик;
  /* Ходить нечем — это когда СЕЙЧАС МОЙ ход, бросок сделан, а сыграть
     нельзя ни одного кубика. У ждущего игрока кубиков ещё нет вовсе (или
     остались чужие от прошлого хода) — ему это поле всегда false, иначе
     соперник увидит чужой тупик как свой. Считать перебором здесь нечего:
     правила уже посчитали максимум при броске. */
  вид.ходитьНечем = вид.яХожу && Boolean(снимок.бросок) && снимок.максимумКубиков === 0;
  вид.завершена = партия.завершена === true;

  /* Последний ход — со всеми перемещениями по порядку: только по ним
     видно, как ехали чужие шашки. Внутреннего имени места здесь нет,
     есть цвет (по нему экран решает, проигрывать ли ход) и признак «мой». */
  if (партия.последнийХод) {
    вид.последнийХод = {
      чей: партия.последнийХод.чей,
      мой: партия.последнийХод.кто === ктоЯ,
      шаги: партия.последнийХод.шаги.map(копияПеремещения),
      запись: партия.последнийХод.запись
    };
  }

  if (партия.завершена) {
    вид.итог = {
      победитель: партия.результат ? (партия.цвета[партия.результат] || null) : null,
      цена: партия.цена || 0,
      видПобеды: партия.видПобеды || null,
      причина: партия.причинаКонца || null,
      яВыиграл: Boolean(партия.результат) && партия.результат === ктоЯ
    };
  }

  return вид;
}

/**
 * Рассказ о случившемся словами. Ни одного глагола прошедшего времени
 * про соперника: русский глагол согласуется с родом, а рода мы не знаем
 * и узнать не можем — «Аня побил» человек прочтёт как неряшливость игры.
 * Поэтому либо настоящее время, либо вовсе без глагола.
 */
function текстСобытия(событие, ктоЯ, места, этоКомпания, подробности) {
  if (!событие || !событие.что) return '';
  const своё = событие.кто === ктоЯ;
  const имя = своё ? 'Вы' : (событие.имя || 'Соперник');

  if (событие.что === 'бросок') return имя + ': бросок кубиков';
  if (событие.что === 'ход') return имя + ': ход';
  if (событие.что === 'пропуск') return имя + ': ходить нечем, ход переходит';
  if (событие.что === 'сдался') return своё ? 'Вы сдались' : 'Соперник сдался';
  if (событие.что === 'вошёл') return имя + ' за доской';
  if (событие.что === 'ушёл' || событие.что === 'ушёл-из-комнаты') {
    return имя + ' больше не играет';
  }
  /* Тот же уход, но не по своей воле: связь молчала три минуты, и уборка
     вывела человека сама (server/комнаты.js, функция «выйти»). */
  if (событие.что === 'пропал' || событие.что === 'пропал-бот') {
    return имя + ' слишком долго не на связи — партия закончена';
  }
  return '';
}

