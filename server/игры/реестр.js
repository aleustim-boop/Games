'use strict';

/* =====================================================================
   РЕЕСТР ИГР — какие игры сервер умеет класть на стол.

   Комната (server/комнаты.js) не знает ни одной игры по имени: она берёт
   игру отсюда и дальше разговаривает с ней на общем языке — договоре
   «игра для сервера». Прихожая, коды комнат, приглашения, выход, возврат,
   уборщик и шлагбаум при этом общие для всех игр: они про СТОЛ, а не
   про то, чем на нём играют.

   ДОГОВОР. Игра обязана дать вот что (подробности — в server/игры/дурак.js,
   там же живой пример):

     имя           как игра называется в запросах: 'дурак', 'шашки';
     мест          { мин, макс, впарах } — сколько мест бывает за столом;
     раздать       начать партию: (ктоНачинает, настройки) → партия;
     чейХод        (партия) → место или null;
     видДляИгрока  (партия, ктоЯ, добавка) → что видит ЭТОТ игрок;
     сделатьХод    (партия, ктоЯ, намерение) → принято или отказ словами;
     ходЗаБота     (партия, место, уровень) → тот же ход, но за бота;
     темпБота      { обычный, внеОчереди } — сколько бот «думает»;
     ходВнеОчереди { ктоСходит, сходить } или null, если такого не бывает;
     напарник      (занятые, место, мест) → место напарника или null.
                   «занятые» — места, где сейчас кто-то сидит, по порядку;
                   «место» — чей напарник нужен; «мест» — сколько мест
                   у стола. Напарник может сидеть на ещё пустом месте:
                   за столом ровно на четыре места пары известны по местам
                   и до полного стола. Игра без пар отвечает null и лишние
                   доводы просто не замечает;
     знаки         { сколько, этоЗнак, этоБросок, голосБота };
     текстСобытия  рассказ о случившемся словами.

   ПОЧЕМУ РЕЕСТР ПРОВЕРЯЕТ ДОГОВОР ПРЯМО ПРИ ЗАПУСКЕ. Игра с полной
   информацией (шашки) выглядит так, будто скрывать ей нечего, и первый
   же соблазн — отдать игроку объект партии целиком. Вместе с доской
   уедет то, чего показывать нельзя: план бота, оценка позиции, а в
   шахматах — заранее посчитанный ответ соперника. Уговоры тут не
   работают, а устройство работает: игра без «видДляИгрока» просто
   не попадает в реестр, и сервер не запускается вовсе. «Мы про это
   не подумали» становится невозможным, а не маловероятным.
   ===================================================================== */

/* Что обязана дать игра. Проверяем именно наличие и тип: договор,
   который никто не проверяет, через месяц договором быть перестаёт. */
const ОБЯЗАТЕЛЬНЫЕ_ФУНКЦИИ = [
  'раздать', 'чейХод', 'видДляИгрока', 'сделатьХод', 'ходЗаБота',
  'напарник', 'текстСобытия'
];

/** Проверить, что игра выполняет договор. Не выполняет — падаем сразу. */
function проверитьДоговор(игра, откуда) {
  if (!игра || typeof игра !== 'object') {
    throw new Error('Реестр игр: ' + откуда + ' — это не игра, а ' + typeof игра);
  }
  if (typeof игра.имя !== 'string' || !игра.имя) {
    throw new Error('Реестр игр: у игры из ' + откуда + ' нет имени');
  }
  for (const что of ОБЯЗАТЕЛЬНЫЕ_ФУНКЦИИ) {
    if (typeof игра[что] !== 'function') {
      throw new Error('Реестр игр: игра «' + игра.имя + '» не даёт «' + что + '». ' +
                      'Договор игры для сервера описан в server/игры/реестр.js');
    }
  }
  const мест = игра.мест;
  if (!мест || !(мест.мин >= 2) || !(мест.макс >= мест.мин)) {
    throw new Error('Реестр игр: игра «' + игра.имя + '» не сказала, сколько бывает мест');
  }
  const знаки = игра.знаки;
  if (!знаки || typeof знаки.сколько !== 'function' || typeof знаки.этоЗнак !== 'function') {
    throw new Error('Реестр игр: игра «' + игра.имя + '» не сказала про знаки внимания');
  }
  return игра;
}

/* Все игры сервера. Список руками, а не обходом папки: сервер должен
   знать наперёд, что он умеет, а не выяснять это по содержимому диска. */
const ИГРЫ = {
  дурак: проверитьДоговор(require('./дурак.js'), 'server/игры/дурак.js'),
  шашки: проверитьДоговор(require('./шашки.js'), 'server/игры/шашки.js')
};

/* Во что играем, если игра не названа. Старые страницы и старые ссылки
   поля «игра» не присылают вовсе, и для них ничего не меняется. */
const ПО_УМОЛЧАНИЮ = 'дурак';

/** Есть ли у нас такая игра. Мусор и незнакомое слово — нет. */
function естьТакая(имя) {
  return typeof имя === 'string' && Object.prototype.hasOwnProperty.call(ИГРЫ, имя);
}

/**
 * Игра по имени. Имя не назвали — дурак, как было всегда.
 * Имя назвали, но такой игры нет — null: пусть отказ будет виден,
 * а не подменён тихой подстановкой другой игры.
 */
function игра(имя) {
  if (имя === undefined || имя === null || имя === '') return ИГРЫ[ПО_УМОЛЧАНИЮ];
  return естьТакая(имя) ? ИГРЫ[имя] : null;
}

/** Имена всех игр — для проверок и для ответа «а что вы умеете». */
function всеИгры() {
  return Object.keys(ИГРЫ);
}

module.exports = {
  ПО_УМОЛЧАНИЮ: ПО_УМОЛЧАНИЮ,
  игра: игра,
  естьТакая: естьТакая,
  всеИгры: всеИгры,
  проверитьДоговор: проверитьДоговор
};
