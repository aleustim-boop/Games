function экранировать(значение) {
  return String(значение).replace(/[&<>"']/g, з => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[з]);
}
function строки(лидеры) {
  return лидеры.length ? '<ol class="лидеры">' + лидеры.map(л => `<li><span class="лидеры__место">${л.место}</span><span>${экранировать(л.имя)}</span></li>`).join('') + '</ol>'
    : '<p class="лидеры__пусто">Пока нет результатов за этот период. Первое место свободно.</p>';
}
function дата(день) { return день.split('-').reverse().join('.'); }
