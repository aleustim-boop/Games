function создать(рейтинг, раздачаДня, время = Date.now, головоломки = require('./лучший-счёт')) {
  let кэш = null;
  let до = 0;
  return function получить() {
    const сейчас = время();
    if (кэш && сейчас < до) return кэш;
    const срез = рейтинг.лидерыНедели(ИГРЫ.map(и => и.игра), сейчас);
    const данные = {
      неделяС: срез.неделяС, сегодня: срез.сегодня, учётС: срез.учётС,
      игры: ИГРЫ.map((и, номер) => ({ название: и.название, метка: и.метка, страница: и.страница,
        лидеры: срез.игры[номер].лидеры.map(л => ({ место: л.место, имя: л.имя })) })),
      головоломки: головоломки.публичныеЛидерыНедели(сейчас),
      раздача: раздачаДня.публичныеЛидеры(срез.сегодня).map(л => ({ место: л.место, имя: л.имя }))
    };
    кэш = { json: JSON.stringify(данные), html: нарисовать(данные) };
    до = сейчас + 60000;
    return кэш;
  };
}
module.exports = { создать, нарисовать };
