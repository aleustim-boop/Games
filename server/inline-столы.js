'use strict';

// Карточка содержит подписанный билет, а не заранее занятую комнату.
// Один билет открывает один стол; просмотр списка не создаёт столов.
const crypto = require('crypto');
const названия = require('./названия.js');
const СРОК = 24 * 60 * 60 * 1000;
const ФОРМА = /^([a-z]+)_src_inline_([a-z0-9]+)_([a-f0-9]{24})_([a-f0-9]{32})$/;

function подпись(текст, секрет) {
  return crypto.createHmac('sha256', секрет).update('inline-стол:' + текст).digest('hex').slice(0, 32);
}

function билет(метка, секрет, сейчас = Date.now()) {
  if (!секрет || !названия.ИГРЫ.some(и => и.метка === метка)) throw new Error('Неизвестная игра или нет ключа');
  const основа = метка + '_src_inline_' + сейчас.toString(36) + '_' + crypto.randomBytes(12).toString('hex');
  return основа + '_' + подпись(основа, секрет);
}

function проверить(значение, секрет, сейчас = Date.now()) {
  if (typeof значение !== 'string' || !секрет) return null;
  const части = ФОРМА.exec(значение);
  if (!части) return null;
  const время = parseInt(части[2], 36);
  if (!Number.isSafeInteger(время) || время > сейчас + 60000 || сейчас - время > СРОК) return null;
  const игра = названия.ИГРЫ.find(и => и.метка === части[1]);
  if (!игра) return null;
  const основа = значение.slice(0, -33);
  if (!crypto.timingSafeEqual(Buffer.from(части[4]), Buffer.from(подпись(основа, секрет)))) return null;
  return { игра: игра.игра, до: время + СРОК };
}

function создатьХранилище() {
  const столы = new Map();
  const новыеУЧеловека = new Map();
  return {
    открыть(значение, секрет, комнаты, адрес, сейчас = Date.now(), номер = адрес) {
      const данные = проверить(значение, секрет, сейчас);
      if (!данные) return { ошибка: 'Приглашение устарело или повреждено. Попросите отправить новую карточку.' };
      for (const [ключ, стол] of столы) if (стол.до < сейчас) столы.delete(ключ);
      const прежний = столы.get(значение);
      if (прежний) {
        if (!комнаты.состояниеСтола(прежний.код).есть) return { ошибка: 'Этот стол уже закрыт. Отправьте новое приглашение.' };
        return { код: прежний.код, игра: данные.игра };
      }
      // Не вытесняем действующие билеты: это создало бы второй стол по той же ссылке.
      if (столы.size >= 5000) return { ошибка: 'Слишком много приглашений. Попробуйте позже.' };
      for (const [кто, запись] of новыеУЧеловека) if (сейчас - запись.с < 0 || сейчас - запись.с >= 60000) новыеУЧеловека.delete(кто);
      const счёт = новыеУЧеловека.get(номер) || { с: сейчас, число: 0 };
      if (счёт.число >= 3) return { ошибка: 'Вы уже открыли три новых стола за минуту. Немного подождите.' };
      // Начинаем с минимального состава самой игры. Иначе, например, в
      // деберце двое друзей оказываются за столом на четверых и не могут начать.
      const стол = комнаты.создатьКомнату(адрес, { игра: данные.игра, безХозяина: true });
      if (!стол.ок) return { ошибка: стол.причина };
      счёт.число++;
      новыеУЧеловека.set(номер, счёт);
      столы.set(значение, { код: стол.код, до: данные.до, вошли: new Set() });
      return { код: стол.код, игра: данные.игра };
    },
    отметитьВход(значение, код, номер) {
      const стол = столы.get(значение);
      if (!стол || стол.код !== код || !номер || стол.вошли.has(номер)) return false;
      стол.вошли.add(номер);
      return true;
    }
  };
}

module.exports = { билет, проверить, создатьХранилище, СРОК };
