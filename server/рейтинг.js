/**
 * Сколько стоит партия с этим соперником при таком исходе.
 * Исход — 'победа', 'ничья' или 'поражение', и он про НАШЕГО игрока.
 */
function ценаСоперника(соперник, исход) {
  const строка = (!соперник || !соперник.этоБот)
    ? ЦЕНА.человек
    : (ЦЕНА[соперник.уровень] || ЦЕНА_НЕИЗВЕСТНОГО_БОТА);
  const цена = строка[исход];
  return цена === undefined ? 0 : цена;
}

/**
 * По какому правилу игрок сыграл эту партию — или пусто, если неизвестно.
 * Признак приносит застолье полем «переводной» (булево, кладут комнаты).
 * Всё, что не булево (поля нет вовсе, старый путь), — «не знаем»: такая
 * партия идёт только в общий счёт.
 */
function правилоИгрока(игрок) {
  if (!игрок || typeof игрок.переводной !== 'boolean') return '';
  return игрок.переводной ? 'переводной' : 'подкидной';
}

/**
 * В каком составе игрок сыграл эту партию — личный или парами.
 * В отличие от правилоИгрока, здесь «неизвестно» не бывает: признак
 * «парами» (булево) кладут все места, откуда вызывается учестьПартию
 * (server/комнаты.js и server/билеты.js), поэтому функция всегда
 * возвращает одно из двух значений.
 */
function составИгрока(игрок) {
  return (игрок && игрок.парами === true) ? 'парами' : 'личный';
}

/** Запись игрока в таблице этой игры; заводим по первой партии. */
function записьИгрока(игра, номер) {
  const таблица = таблицаИгры(игра);
  if (!таблица.has(номер)) таблица.set(номер, пустаяЗапись(номер));
  return таблица.get(номер);
}

/**
 * Добавить очки с оглядкой на дневной потолок для ботов.
 * Отвечает, сколько добавилось на самом деле.
 */
function начислить(запись, откуда, сколько, сегодня) {
  if (сколько <= 0) return 0;
  if (откуда === 'человек') {
    if (запись.деньЛюдей !== сегодня) {
      запись.деньЛюдей = сегодня;
      запись.очкиОтЛюдейЗаДень = 0;
      запись.партийСЧеловекомЗаДень = {};
    }
    const осталосьУЛюдей = Math.max(0, ПОТОЛОК_ОТ_ЛЮДЕЙ_В_СУТКИ - запись.очкиОтЛюдейЗаДень);
    const дадимЗаЛюдей = Math.min(сколько, осталосьУЛюдей);
    запись.очкиОтЛюдейЗаДень += дадимЗаЛюдей;
    запись.очки += дадимЗаЛюдей;
    return дадимЗаЛюдей;
  }
  if (запись.деньБотов !== сегодня) {
    запись.деньБотов = сегодня;
    запись.очкиОтБотовЗаДень = 0;
  }
  const осталось = Math.max(0, ПОТОЛОК_ОТ_БОТОВ_В_СУТКИ - запись.очкиОтБотовЗаДень);
  const дадим = Math.min(сколько, осталось);
  запись.очкиОтБотовЗаДень += дадим;
  запись.очки += дадим;
  return дадим;
}

/**
 * Идёт ли эта пара людей ещё в зачёт сегодня — и отмечаем партию.
 * Первые пять партий с ОДНИМ И ТЕМ ЖЕ человеком за сутки считаются,
 * дальше партия играется, но очков за неё нет: так ограничитель бьёт
 * по сговору, а не по тому, кто играет со многими.
 */
function параЕщёВЗачёте(запись, номерСоперника, сегодня) {
  if (запись.деньЛюдей !== сегодня) {
    запись.деньЛюдей = сегодня;
    запись.очкиОтЛюдейЗаДень = 0;
    запись.партийСЧеловекомЗаДень = {};
  }
  const ключ = String(номерСоперника);
  const было = Number(запись.партийСЧеловекомЗаДень[ключ]) || 0;
  запись.партийСЧеловекомЗаДень[ключ] = было + 1;
  return было < ПАРТИЙ_С_ОДНИМ_ЧЕЛОВЕКОМ_В_СУТКИ;
}

/**
 * Записать итог партии.
 *
 * Что приходит: имя игры и список сидевших за столом. Каждый — это
 * { номер, имя, этоБот, уровень, победил, ничья }. Номер есть только
 * у тех, кто играет из Telegram; остальных просто не считаем — опознать
 * их нечем, а выдумывать игрока ради строчки в таблице нельзя.
 *
 * Очки начисляются за КАЖДОГО обыгранного за столом: победа над тремя
 * людьми в компании и правда стоит втрое дороже победы над одним.
 *
 * Отвечает, сколько очков добавилось каждому: { номер: очков }. Это нужно
 * билетам партий с ботом (server/билеты.js) — сказать человеку «+2», не
 * перебирая таблицу до и после. Комнаты ответ не читают.
 *
 * ключПартии (необязательный третий довод) — строка, однозначно называющая
 * именно эту партию (у комнат: код + время рождения комнаты + номер партии
 * внутри неё, см. server/комнаты.js; у билетов — номер билета, см.
 * server/билеты.js). Партия с уже знакомым ключом — повторная доставка
 * одного и того же события: очков не начисляем и силу не трогаем, отвечаем
 * пустым {}. Без ключа (старые вызовы, проверки) память ключей не трогаем
 * вовсе — партия считается как раньше, при каждом вызове заново.
 */
function учестьПартию(игра, застольем, ключПартии) {
  if (!ужеЗагрузили) загрузить();

  const ключ = (typeof ключПартии === 'string' && ключПартии) ? ключПартии : null;
  if (ключ && учтённыеПартииНабор.has(ключ)) {
    console.log('[рейтинг] партия «' + ключ + '» уже учтена — повторную доставку пропускаем');
    return {};
  }

  // Партии играются часто — этим же вызовом держим снимок вчерашних мест свежим.
  обновитьСнимокЕслиНужно();
  const добавлено = {};
  if (!Array.isArray(застольем) || застольем.length < 2) return добавлено;

  /* Та же партия идёт и во вторую меру — силу. Зовём её отсюда, а не из
     комнат, чтобы у конца партии осталась ровно одна дверь: забыть одну
     из двух мер при следующей игре тогда просто негде. Своя память,
     свои правила и свой файл у силы отдельные. */
  сила.учесть(игра, застольем);

  const сегодня = ключДня();
  let менялось = false;

  for (const игрок of застольем) {
    if (!игрок || игрок.этоБот || !этоНомерИгрока(игрок.номер)) continue;

    const запись = записьИгрока(игра, игрок.номер);
    if (типИмени(игрок.имя)) запись.имя = типИмени(игрок.имя);
    добавлено[игрок.номер] = добавлено[игрок.номер] || 0;
    запись.партий++;
    запись.последняяИгра = сегодня;
    менялось = true;

    /* Считаем ЛЮБОЙ исход, а не только победу. Раньше проигравший до
       начисления не доходил вовсе, и правило «за поражение живому очки
       всё равно капают» не работало бы ни у кого. */
    const исход = игрок.ничья ? 'ничья' : (игрок.победил ? 'победа' : 'поражение');
    if (исход === 'ничья') запись.ничьих++;
    if (исход === 'победа') запись.побед++;

    /* Половина счёта по правилу партии. Правило приносит застолье полем
       «переводной» (булево). Поля нет — значит про правило неизвестно
       (партия с ботом в браузере, старый путь): такая партия идёт только
       в общий счёт, а обе половины остаются нетронутыми. */
    const правило = правилоИгрока(игрок);
    const половина = правило ? счётчикПравила(запись, правило) : null;
    if (половина) {
      половина.партий++;
      if (исход === 'ничья') половина.ничьих++;
      if (исход === 'победа') половина.побед++;
    }

    /* Половина счёта по составу игроков. В отличие от правила, состав
       известен всегда, поэтому половинаСостава — не null и используется
       без условной обёртки. */
    const состав = составИгрока(игрок);
    const половинаСостава = счётчикСостава(запись, состав);
    половинаСостава.партий++;
    if (исход === 'ничья') половинаСостава.ничьих++;
    if (исход === 'победа') половинаСостава.побед++;

    for (const другой of застольем) {
      if (другой === игрок) continue;
      const этоБот = Boolean(другой && другой.этоБот);
      /* С живым соперником сперва спрашиваем ограничитель сговора: он же
         и отмечает партию. Порядок важен — отмечать надо каждую партию
         пары, даже ту, за которую очков уже не дадим. */
      if (!этоБот && !параЕщёВЗачёте(запись, другой && другой.номер, сегодня)) continue;
      /* В «2 на 2» напарник сидит за тем же столом, что и соперники, но
         очков за него давать надо вполовину меньше: выигрыш сделан не
         в одиночку. Тот же множитель 0.5, что у силы игроков. */
      const этоНапарник = Boolean(игрок.напарник) && другой && другой.номер === игрок.напарник;
      const цена = ценаСоперника(другой, исход) * (этоНапарник ? 0.5 : 1);
      const прибавка = начислить(запись, этоБот ? 'бот' : 'человек',
                                 цена, сегодня);
      добавлено[игрок.номер] += прибавка;
      /* В половину кладём РОВНО то, что легло в общий счёт: суточный
         потолок один на обе половины (решение штаба). Иначе, играя
         попеременно в оба правила, можно было бы взять вдвое больше. */
      if (половина) половина.очки += прибавка;
      половинаСостава.очки += прибавка;
    }
  }

  if (ключ) {
    /* Партия обработана до конца — запоминаем ключ, чтобы следующая
       доставка того же события отсеклась в самом начале функции.
       Вытесняем самый старый ключ, если уже упёрлись в потолок. */
    учтённыеПартииНабор.add(ключ);
    учтённыеПартии.push(ключ);
    while (учтённыеПартии.length > МАКС_УЧТЁННЫХ_ПАРТИЙ) {
      учтённыеПартииНабор.delete(учтённыеПартии.shift());
    }
    /* Ключ — тоже часть памяти на диске и обязан пережить перезапуск,
       даже если самой партии не досталось очков (лёгкий бот, потолок):
       иначе после падения сервера защита начнёт работать не сразу. */
    записатьПогодя();
  }

  if (менялось) {
    /* Кому-то реально упали очки — это и есть то самое «важное», которое
       игрок увидит сразу на экране итога партии: пишем на диск немедленно,
       не дожидаясь пяти секунд. Партия сыграна, но очков никому не дало
       (лёгкий бот, исчерпанный суточный потолок) — такую мелочь, как
       раньше, можно спокойно отложить: пропавшая при падении «партия без
       очков» не создаёт у игрока ощущения, что рейтинг врёт. */
    let начисленоВсего = 0;
    for (const номер in добавлено) начисленоВсего += добавлено[номер];
    if (начисленоВсего > 0) записатьСрочно();
    else записатьПогодя();
  }
  return добавлено;
}

/**
 * Сколько очков за ботов этот человек ещё может взять сегодня в этой игре.
 * Нужно билетам партий с ботом: когда потолок исчерпан, партию не учитывают
 * вовсе — ни очков, ни счётчиков партий и побед (см. server/билеты.js).
 */
function осталосьОтБотовСегодня(игра, номер) {
  if (!ужеЗагрузили) загрузить();
  const запись = таблицаИгры(игра).get(номер);
  if (!запись || запись.деньБотов !== ключДня()) return ПОТОЛОК_ОТ_БОТОВ_В_СУТКИ;
  return Math.max(0, ПОТОЛОК_ОТ_БОТОВ_В_СУТКИ - запись.очкиОтБотовЗаДень);
}

/** Имя как строка разумной длины — или пусто. */
function типИмени(имя) {
  if (typeof имя !== 'string') return '';
  const чистое = имя.trim();
  return чистое ? чистое.slice(0, 40) : '';
}

