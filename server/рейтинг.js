/** Имена правил, по которым ведём отдельный счёт. */
const ПРАВИЛА = ['подкидной', 'переводной'];

/** Имена составов, по которым ведём отдельный счёт. */
const СОСТАВЫ = ['личный', 'парами'];

/** Нулевые счётчики одной половины (одного правила). */
function пустойСчётчикПравила() {
  return { очки: 0, побед: 0, ничьих: 0, партий: 0 };
}

/** Нулевые счётчики сразу по обоим правилам. */
function пустыеСчётчикиПоПравилам() {
  const счётчики = {};
  for (const правило of ПРАВИЛА) счётчики[правило] = пустойСчётчикПравила();
  return счётчики;
}

/** Это одно из известных правил? Всё остальное — общий счёт. */
function этоПравило(правило) {
  return ПРАВИЛА.indexOf(правило) !== -1;
}

/**
 * Счётчики этой половины у записи; заводим, если их ещё нет.
 * Нужно на случай записи, пришедшей из старого файла или заведённой
 * до появления второй оси: падать из-за отсутствующего поля нельзя.
 */
function счётчикПравила(запись, правило) {
  if (!запись.поПравилу || typeof запись.поПравилу !== 'object') {
    запись.поПравилу = пустыеСчётчикиПоПравилам();
  }
  const был = запись.поПравилу[правило];
  if (!был || typeof был !== 'object') {
    запись.поПравилу[правило] = пустойСчётчикПравила();
  }
  return запись.поПравилу[правило];
}

/** Нулевые счётчики одной половины (одного состава). */
function пустойСчётчикСостава() {
  return { очки: 0, побед: 0, ничьих: 0, партий: 0 };
}

/** Нулевые счётчики сразу по обоим составам. */
function пустыеСчётчикиПоСоставу() {
  const счётчики = {};
  for (const состав of СОСТАВЫ) счётчики[состав] = пустойСчётчикСостава();
  return счётчики;
}

/** Это один из известных составов? Всё остальное — общий счёт. */
function этоСостав(состав) {
  return СОСТАВЫ.indexOf(состав) !== -1;
}

/**
 * Счётчики этой половины у записи; заводим, если их ещё нет.
 * Нужно на случай записи, пришедшей из старого файла или заведённой
 * до появления третьей оси: падать из-за отсутствующего поля нельзя.
 */
function счётчикСостава(запись, состав) {
  if (!запись.поСоставу || typeof запись.поСоставу !== 'object') {
    запись.поСоставу = пустыеСчётчикиПоСоставу();
  }
  const был = запись.поСоставу[состав];
  if (!был || typeof был !== 'object') {
    запись.поСоставу[состав] = пустойСчётчикСостава();
  }
  return запись.поСоставу[состав];
}

