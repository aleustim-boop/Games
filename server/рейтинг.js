/** Прочитать файл. Нет файла или он испорчен — начинаем с чистого листа. */
function загрузить() {
  ужеЗагрузили = true;
  let прочитанное = null;
  try {
    прочитанное = JSON.parse(fs.readFileSync(файл(), 'utf8'));
  } catch (сбой) {
    return;             // файла нет или он испорчен — это не беда
  }
  if (!прочитанное || !Array.isArray(прочитанное.игроки)) return;

  for (const запись of прочитанное.игроки) {
    if (!запись || !этоНомерИгрока(запись.номер)) continue;
    const свежая = пустаяЗапись(запись.номер);
    свежая.имя = typeof запись.имя === 'string' ? запись.имя : '';
    свежая.очки = Number(запись.очки) || 0;
    свежая.побед = Number(запись.побед) || 0;
    свежая.ничьих = Number(запись.ничьих) || 0;
    свежая.партий = Number(запись.партий) || 0;
    свежая.деньБотов = typeof запись.деньБотов === 'string' ? запись.деньБотов : '';
    свежая.очкиОтБотовЗаДень = Number(запись.очкиОтБотовЗаДень) || 0;
    свежая.деньЛюдей = typeof запись.деньЛюдей === 'string' ? запись.деньЛюдей : '';
    свежая.очкиОтЛюдейЗаДень = Number(запись.очкиОтЛюдейЗаДень) || 0;
    свежая.партийСЧеловекомЗаДень = (запись.партийСЧеловекомЗаДень &&
      typeof запись.партийСЧеловекомЗаДень === 'object')
      ? Object.assign({}, запись.партийСЧеловекомЗаДень) : {};
    свежая.последняяИгра = typeof запись.последняяИгра === 'string'
      ? запись.последняяИгра : '';
    /* Счёт по правилам: в файлах, записанных до появления второй оси,
       этого поля нет вовсе — тогда обе половины просто остаются
       нулевыми, а общий счёт выше читается как раньше и не теряется. */
    for (const правило of ПРАВИЛА) {
      const был = запись.поПравилу && typeof запись.поПравилу === 'object'
        ? запись.поПравилу[правило] : null;
      if (!был || typeof был !== 'object') continue;
      const стал = счётчикПравила(свежая, правило);
      стал.очки = Number(был.очки) || 0;
      стал.побед = Number(был.побед) || 0;
      стал.ничьих = Number(был.ничьих) || 0;
      стал.партий = Number(был.партий) || 0;
    }
    /* Счёт по составу: та же логика, что и по правилам, — в файлах без
       этого поля обе половины остаются нулевыми, общий счёт не теряется. */
    for (const состав of СОСТАВЫ) {
      const был = запись.поСоставу && typeof запись.поСоставу === 'object'
        ? запись.поСоставу[состав] : null;
      if (!был || typeof был !== 'object') continue;
      const стал = счётчикСостава(свежая, состав);
      стал.очки = Number(был.очки) || 0;
      стал.побед = Number(был.побед) || 0;
      стал.ничьих = Number(был.ничьих) || 0;
      стал.партий = Number(был.партий) || 0;
    }
    таблицаИгры(запись.игра).set(запись.номер, свежая);
  }

  /* Ключи уже учтённых партий переживают перезапуск — иначе защита от
     повторной доставки работала бы только до первого падения сервера.
     Старого файла без поля «учтённые» не боимся: список остаётся пустым,
     как и был до появления защиты. */
  учтённыеПартии = [];
  учтённыеПартииНабор = new Set();
  if (Array.isArray(прочитанное.учтённые)) {
    for (const ключ of прочитанное.учтённые) {
      if (typeof ключ !== 'string' || !ключ || учтённыеПартииНабор.has(ключ)) continue;
      учтённыеПартииНабор.add(ключ);
      учтённыеПартии.push(ключ);
    }
    // Старый файл теоретически мог накопить больше потолка — обрежем как обычно.
    while (учтённыеПартии.length > МАКС_УЧТЁННЫХ_ПАРТИЙ) {
      учтённыеПартииНабор.delete(учтённыеПартии.shift());
    }
  }

  прибраться();
}

/** Сложить память в файл. Молча: беда с диском не повод ронять партии. */
function записатьСейчас() {
  естьЧтоЗаписать = false;
  const список = [];
  for (const [игра, таблица] of таблицы) {
    for (const запись of таблица.values()) {
      список.push({
        игра: игра,
        номер: запись.номер,
        имя: запись.имя,
        очки: запись.очки,
        побед: запись.побед,
        ничьих: запись.ничьих,
        партий: запись.партий,
        деньБотов: запись.деньБотов,
        очкиОтБотовЗаДень: запись.очкиОтБотовЗаДень,
        деньЛюдей: запись.деньЛюдей,
        очкиОтЛюдейЗаДень: запись.очкиОтЛюдейЗаДень,
        партийСЧеловекомЗаДень: запись.партийСЧеловекомЗаДень,
        последняяИгра: запись.последняяИгра,
        поПравилу: запись.поПравилу,
        поСоставу: запись.поСоставу
      });
    }
  }
  try {
    fs.mkdirSync(папка(), { recursive: true });
    // Во временный файл и переименование: обрывка на диске не бывает.
    fs.writeFileSync(файлПокаПишем(), JSON.stringify({
      игроки: список,
      // Ключи учтённых партий — та же защита от повтора, но переживает перезапуск.
      учтённые: учтённыеПартии
    }), 'utf8');
    fs.renameSync(файлПокаПишем(), файл());
  } catch (сбой) {
    /* Не записалось — память останется до следующей попытки. */
  }
}

/** Пометить, что память изменилась. Настоящая запись — чуть погодя. */
function записатьПогодя() {
  if (!записьРазрешена) return;
  естьЧтоЗаписать = true;
  if (таймерЗаписи !== null) return;
  таймерЗаписи = setTimeout(function () {
    таймерЗаписи = null;
    if (естьЧтоЗаписать) записатьСейчас();
  }, ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ);
  if (таймерЗаписи.unref) таймерЗаписи.unref();
}

/**
 * Записать НЕМЕДЛЕННО, без пятисекундного ожидания. Зовём, когда партия
 * реально начислила кому-то очки — это то, что человек ждёт увидеть
 * в таблице сразу после игры, и потерю нельзя списать на «мелочь».
 * Отменяет отложенный таймер, если он уже тикал по другому, менее
 * важному поводу: раз пишем прямо сейчас, ждать больше нечего. Ошибку
 * записи (диск занят, файла нет прав) — как и раньше, глотаем внутри
 * записатьСейчас(): партию живых людей класть из-за этого нельзя.
 */
function записатьСрочно() {
  if (!записьРазрешена) return;
  if (таймерЗаписи !== null) {
    clearTimeout(таймерЗаписи);
    таймерЗаписи = null;
  }
  записатьСейчас();
}

/** Записать прямо сейчас (нужно при остановке сервера). */
function дописать() {
  if (таймерЗаписи !== null) {
    clearTimeout(таймерЗаписи);
    таймерЗаписи = null;
  }
  if (естьЧтоЗаписать) записатьСейчас();
  // Силу дописываем тем же движением: сервер останавливают один раз.
  сила.дописать();
}

/** Забыть тех, кто давно не играл. */
function прибраться() {
  const край = new Date();
  край.setDate(край.getDate() - ХРАНИМ_ДНЕЙ);
  const самыйСтарый = ключДня(край.getTime());
  for (const таблица of таблицы.values()) {
    for (const [номер, запись] of таблица) {
      if (запись.последняяИгра && запись.последняяИгра < самыйСтарый) {
        таблица.delete(номер);
      }
    }
  }
}

/* ---------------------------------------------------------------------
   Снимок вчерашних мест — для стрелки «место выросло/упало»

   ЧТО ЗНАЧИТ «РАЗ В СУТКИ». Снимок берём не по таймеру, а лениво: каждая
   внешняя точка входа (учестьПартию и срезы ниже — срезДляИгрока,
   срезПоВсемИграм, срезПоСписку, срезПоВсемИграмПоСписку) первым делом
   спрашивает обновитьСнимокЕслиНужно(). Если календарный день (ключДня(),
   по местному времени) с прошлого снимка уже сменился — считаем места
   заново и пишем на диск; иначе — просто сравнение двух строк, почти
   бесплатно. Игроки заходят в рейтинг и играют партии постоянно, так
   что снимок не залёживается, а отдельный таймер в фоне не нужен.

   ЧТО ХРАНИМ. Ровно два снимка — «сегодня» (места на момент последнего
   пересчёта) и «вчера» (места на момент предыдущего пересчёта). Третий
   и дальше никому не нужен — стрелка смотрит только на один день назад,
   а хранить больше — раздувать файл без пользы.

   СПЯЩИЙ СЕРВЕР. «Сегодня» становится «вчера» ТОЛЬКО если разница между
   ними — ровно один календарный день. Сервер стоял трое суток (или это
   первый запуск вовсе) — старые места слишком старые, чтобы звать их
   вчерашними: «вчера» становится честным «нет данных», а старый снимок
   просто теряется. Тот же выбор, что «нет вчерашнего места — движения
   нет», только для целого файла, а не для одного игрока.

   НОВЫЙ ИГРОК. Если вчера человека не было в снимке (первая партия,
   впервые попал в топ) — вчерашнего места у него правда нет: движение —
   'нетДанных', а не «вырос с нуля». Врать движением нельзя — тот же
   принцип, каким рейтинг уже не платит выдуманных очков (см. ЦЕНА).

   ЧЬИ МЕСТА СЧИТАЕМ. Место в снимке — это место в ОБЩЕМ счёте игры (без
   разбивки на правило/состав) и отдельно место в сумме «все игры»: это
   единственные два списка с ГЛОБАЛЬНЫМ рангом по всей таблице. У половин
   по правилу/составу место совсем другое (сортировка по своей половине
   счёта), а у среза «только друзья» место ЛОКАЛЬНОЕ — 1..N внутри
   урезанного списка друзей, не позиция в общей таблице (см. срезИзСписка).
   Сравнивать такое место со вчерашним глобальным было бы неправдой —
   поэтому туда ключ снимка не передают вовсе, и поля «движение» там нет.
   --------------------------------------------------------------------- */

/** Память последних двух снимков дня: { вчера, сегодня }, либо null внутри. */
let снимокМест = { вчера: null, сегодня: null };
let ужеЗагрузилиМеста = false;

/** Прочитать снимок мест с диска. Нет файла или он испорчен — начинаем с нуля. */
function загрузитьМеста() {
  ужеЗагрузилиМеста = true;
  try {
    const прочитанное = JSON.parse(fs.readFileSync(файлМест(), 'utf8'));
    снимокМест = {
      вчера: частьСнимкаМест(прочитанное && прочитанное.вчера),
      сегодня: частьСнимкаМест(прочитанное && прочитанное.сегодня)
    };
  } catch (сбой) {
    снимокМест = { вчера: null, сегодня: null };
  }
}

/** Одна половина снимка («вчера» или «сегодня») — только в ожидаемой форме. */
function частьСнимкаМест(часть) {
  if (!часть || typeof часть.день !== 'string' || !часть.места || typeof часть.места !== 'object') {
    return null;
  }
  return { день: часть.день, места: часть.места };
}

/** Сложить снимок мест на диск — тем же приёмом, что и очки (temp + rename). */
function записатьМеста() {
  if (!записьРазрешена) return;
  try {
    fs.mkdirSync(папка(), { recursive: true });
    fs.writeFileSync(файлМестПокаПишем(), JSON.stringify(снимокМест), 'utf8');
    fs.renameSync(файлМестПокаПишем(), файлМест());
  } catch (сбой) {
    /* Не записалось — переживём: при следующей смене суток попробуем снова. */
  }
}

/** Место каждого номера в уже отсортированном списке: {"номер": место}. */
function местаИзСписка(список) {
  const места = {};
  for (let индекс = 0; индекс < список.length; индекс++) {
    места[String(список[индекс].номер)] = индекс + 1;
  }
  return места;
}

/** Текущие места по каждой игре, у которой уже есть таблица, плюс «все игры». */
function текущиеМестаПоИграм() {
  const места = {};
  for (const [имяИгры] of таблицы) {
    места[имяИгры] = местаИзСписка(порядок(имяИгры));
  }
  места._всеИгры = местаИзСписка(списокПоВсемИграм());
  return места;
}

/**
 * Если календарный день сменился с прошлого снимка — снять новый и
 * записать на диск. Дешёвая на обычном вызове (сравнение двух строк),
 * зовут её все внешние точки входа перед тем, как читать снимокМест.
 */
function обновитьСнимокЕслиНужно() {
  if (!ужеЗагрузили) загрузить();
  if (!ужеЗагрузилиМеста) загрузитьМеста();

  const сегодняшнийКлюч = ключДня();
  if (снимокМест.сегодня && снимокМест.сегодня.день === сегодняшнийКлюч) return;

  /* Прежнее «сегодня» становится «вчера» только если это буквально вчера
     по календарю — иначе сервер спал больше суток, и мест «на вчера»
     у нас на самом деле нет (см. пояснение в шапке раздела). */
  /* Вычисляем вчерашний день календарно через setDate, не минус 24 часа:
     в ночь перевода часов сутки короче, и минус 24ч уедет на позапрошлый день. */
  const вчера = new Date();
  вчера.setDate(вчера.getDate() - 1);
  const вчерашнийКлюч = ключДня(вчера.getTime());
  const новоеВчера = (снимокМест.сегодня && снимокМест.сегодня.день === вчерашнийКлюч)
    ? снимокМест.сегодня
    : null;

  снимокМест = {
    вчера: новоеВчера,
    сегодня: { день: сегодняшнийКлюч, места: текущиеМестаПоИграм() }
  };
  записатьМеста();
}

/**
 * Движение места этого номера в списке ключСнимка ('имя игры' или
 * '_всеИгры'): { движение, сдвиг }, где движение —
 * 'выросло' | 'упало' | 'безИзменений' | 'нетДанных', а сдвиг — сколько
 * мест прошли (вчерашнее место минус сегодняшнее, по модулю); для
 * «безИзменений» сдвиг равен 0, для «нетДанных» поля сдвиг нет.
 * Зовут, только когда ключСнимка не пуст — для половин по правилу/составу
 * и для среза «только друзья» место не глобальное (см. шапку раздела),
 * и функцию туда не зовут вовсе.
 */
function движениеМеста(ключСнимка, номер, текущееМесто) {
  const местаВчера = снимокМест.вчера && снимокМест.вчера.места
    ? снимокМест.вчера.места[ключСнимка]
    : null;
  if (!местаВчера) return { движение: 'нетДанных' };
  const вчерашнееМесто = местаВчера[String(номер)];
  if (вчерашнееМесто === undefined) return { движение: 'нетДанных' };
  if (текущееМесто < вчерашнееМесто) {
    return { движение: 'выросло', сдвиг: вчерашнееМесто - текущееМесто };
  }
  if (текущееМесто > вчерашнееМесто) {
    return { движение: 'упало', сдвиг: текущееМесто - вчерашнееМесто };
  }
  return { движение: 'безИзменений', сдвиг: 0 };
}

