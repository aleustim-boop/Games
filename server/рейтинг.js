/* =====================================================================
   РЕЙТИНГ ИГРОКОВ: кто играет сильнее.

   Зачем. Владелец попросил рейтинг вслух: «ещё необходимо сделать
   рейтинг игроков». Простой счёт побед на этот вопрос не отвечает:
   кто сыграл двести партий с лёгким ботом, обгонит того, кто выиграл
   двадцать у живых людей, — и таблица будет показывать усидчивость,
   а не силу.

   ЧТО СЧИТАЕМ СИЛОЙ — очки за победы, и вес победы зависит от того,
   кого обыграли:

     живой человек   +10 за каждого обыгранного за столом
     сложный бот     +6
     обычный бот     +3
     лёгкий бот      +1
     ничья           половина веса (в шашках ничьи бывают часто)
     поражение        0

   Отрицательных очков нет нарочно. Отнимать за проигрыш — значит
   отбивать желание играть, а у нас игра, а не спорт: человек садится
   за стол отдохнуть, а не защищать разряд.

   Числа подобраны так, чтобы правило «победы над людьми весят больше»
   выполнялось буквально, а не на словах: двести партий с лёгким ботом
   дают те же 200 очков, что двадцать побед над живыми людьми.

   ПОТОЛОК ОЧКОВ ОТ БОТОВ — 12 в сутки. Бот всегда под рукой и никогда
   не отказывается играть, поэтому очки от него можно копить бесконечно:
   за вечер упорный человек обошёл бы того, кто честно выигрывает у людей.
   Двенадцать — это две победы над сложным ботом, четыре над обычным
   или дюжина над лёгким: обычному игроку потолок не мешает вовсе, а
   накрутку останавливает. Очки за победы над людьми не ограничены ничем:
   там накрутить нельзя, для этого нужен второй настоящий человек.

   ТАБЛИЦЫ РАЗДЕЛЬНЫЕ ПО ИГРАМ. Сила в дураке ничего не говорит о силе
   в шашках; общий список сложил бы карты с шашками и стал бы
   бессмысленным.

   КОГО СЧИТАЕМ. Только тех, кто открыл игру в Telegram: опознать игрока
   можно единственно по номеру из проверенной подписи (тот же источник,
   что у знакомых). Кто играет из браузера, в таблицу не попадает —
   и дверь честно говорит ему об этом словами.

   ЧТО ХРАНИМ И ЧЕГО НЕ ХРАНИМ. Номер игрока в Telegram, имя, которым он
   назвался за столом, очки, победы, партии и день последней игры. Ни
   карт, ни кодов комнат, ни того, кто именно кого обыграл. Файл лежит
   в server/данные — там же, где знакомые и статистика, и по тем же
   правилам: в git не едет, пишется отложенно и через временный файл,
   чтобы перезапуск не оставил обрывка.

   НАРУЖУ НОМЕР НЕ УХОДИТ НИКОГДА. Ответ собирается вручную, поле за
   полем (см. срезДляИгрока): взять готовую запись целиком нельзя —
   вместе с ней уехал бы номер, и такую утечку потом ищут неделями.

   РЯДОМ ЕСТЬ ВТОРАЯ МЕРА — СИЛА (см. server/сила-игроков.js). Владелец
   просил обе: «нужен рейтинг общий… так же отдельно нужен рейтинг игры
   с живым игроком, там всё зависеть должно от уровня игрока, против
   которого ты играешь». Здесь копятся очки за сыгранное и выигранное,
   там считается, кто играет сильнее. Мера разная нарочно: за столом
   вшестером победа над пятью и вправду стоит впятеро больше очков —
   это пять побед; но о силе она говорит не больше одной партии.

   Стыковка сделана в одном месте: «учестьПартию» передаёт то же самое
   застолье силе, а «срезДляИгрока» кладёт её ответ в поле «сила».
   Ни комнатам, ни серверу знать о двух файлах отдельно не нужно.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const сила = require('./сила-игроков.js');

/* Где лежат данные, спрашиваем при каждом обращении — у одного
   места на весь сервер (см. server/папка-данных.js). Своей копии пути
   здесь нет нарочно: пока он был зашит тут, проверки из tests/ писали
   прямо в боевую папку и однажды стёрли настоящие данные владельца. */
const гдеДанные = require('./папка-данных.js');

/** Папка с данными прямо сейчас. */
function папка() { return гдеДанные.папка(); }

/** Наш файл памяти. */
function файл() { return гдеДанные.файл('рейтинг.json'); }

/** Временный файл, в который пишем перед переименованием. */
function файлПокаПишем() { return файл() + '.пишем'; }

/* Сколько очков даёт победа над этим соперником. Слово «человек» — это
   живой игрок; остальное — уровни ботов, как их называет игра. */
const ЦЕНА_ПОБЕДЫ = {
  человек: 10,
  сложный: 6,
  обычный: 3,
  лёгкий: 1
};

/* Уровень бота, если игра его не назвала: считаем самым дешёвым.
   Ошибиться в меньшую сторону здесь честнее — иначе накрутка. */
const ЦЕНА_НЕИЗВЕСТНОГО_БОТА = 1;

/* Потолок очков от ботов за сутки — см. пояснение в шапке. */
const ПОТОЛОК_ОТ_БОТОВ_В_СУТКИ = 12;

/* Сколько помним неигравшего человека. Дольше, чем знакомых (60 дней):
   рейтинг — это накопленное, и терять его за два месяца тишины обидно.
   Полгода — разумная середина между «помним» и «файл растёт вечно». */
const ХРАНИМ_ДНЕЙ = 180;

/* Сколько строк вокруг себя показываем и сколько строк верхушки.
   Человеку на 340-м месте первая десятка бесполезна — ему нужны соседи. */
const СОСЕДЕЙ_СВЕРХУ = 5;
const СОСЕДЕЙ_СНИЗУ = 5;
const ВЕРХУШКИ = 3;

/* Пишем не сразу: конец партии трогает память несколько раз подряд. */
const ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ = 5000;

/* Память: игра → номер игрока → запись. Держим в двух уровнях, потому
   что таблицы у игр раздельные и смешивать их нельзя. */
const таблицы = new Map();

let записьРазрешена = false;
let ужеЗагрузили = false;
let таймерЗаписи = null;
let естьЧтоЗаписать = false;

/** Разрешить запись на диск (сервер с «--без-памяти» её не включает). */
function включитьЗапись() {
  записьРазрешена = true;
  // Сила хранится в своём файле, но живёт по тем же правилам.
  сила.включитьЗапись();
}

/** «2026-09-08» по местному времени. */
function ключДня(время) {
  const дата = new Date(время === undefined ? Date.now() : время);
  const месяц = String(дата.getMonth() + 1).padStart(2, '0');
  const число = String(дата.getDate()).padStart(2, '0');
  return дата.getFullYear() + '-' + месяц + '-' + число;
}

/** Похоже ли это на настоящий номер игрока в Telegram. */
function этоНомерИгрока(номер) {
  return Number.isInteger(номер) && номер > 0;
}

/** Таблица этой игры; заводим по первому обращению. */
function таблицаИгры(игра) {
  const имя = typeof игра === 'string' && игра ? игра : 'дурак';
  if (!таблицы.has(имя)) таблицы.set(имя, new Map());
  return таблицы.get(имя);
}

/** Пустая запись игрока. */
function пустаяЗапись(номер) {
  return {
    номер: номер,
    имя: '',
    очки: 0,
    побед: 0,
    ничьих: 0,
    партий: 0,
    /* Сколько очков этот человек уже взял с ботов сегодня — для потолка.
       Храним вместе с днём: наступил новый день, счёт начинается заново. */
    деньБотов: '',
    очкиОтБотовЗаДень: 0,
    последняяИгра: ''
  };
}

/* ---------------------------------------------------------------------
   Память на диске
   --------------------------------------------------------------------- */

/** Прочитать файл. Нет файла или он испорчен — начинаем с чистого листа. */
function загрузить() {
  ужеЗагрузили = true;
  let прочитанное = null;
  try {
    прочитанное = JSON.parse(fs.readFileSync(файл(), 'utf8'));
  } catch (сбой) {
    return;             // файла нет или он испорчен — это не беда
  }
  if (!прочитанное || !Array.isArray(прочитанное.игроки)) return;

  for (const запись of прочитанное.игроки) {
    if (!запись || !этоНомерИгрока(запись.номер)) continue;
    const свежая = пустаяЗапись(запись.номер);
    свежая.имя = typeof запись.имя === 'string' ? запись.имя : '';
    свежая.очки = Number(запись.очки) || 0;
    свежая.побед = Number(запись.побед) || 0;
    свежая.ничьих = Number(запись.ничьих) || 0;
    свежая.партий = Number(запись.партий) || 0;
    свежая.деньБотов = typeof запись.деньБотов === 'string' ? запись.деньБотов : '';
    свежая.очкиОтБотовЗаДень = Number(запись.очкиОтБотовЗаДень) || 0;
    свежая.последняяИгра = typeof запись.последняяИгра === 'string'
      ? запись.последняяИгра : '';
    таблицаИгры(запись.игра).set(запись.номер, свежая);
  }
  прибраться();
}

/** Сложить память в файл. Молча: беда с диском не повод ронять партии. */
function записатьСейчас() {
  естьЧтоЗаписать = false;
  const список = [];
  for (const [игра, таблица] of таблицы) {
    for (const запись of таблица.values()) {
      список.push({
        игра: игра,
        номер: запись.номер,
        имя: запись.имя,
        очки: запись.очки,
        побед: запись.побед,
        ничьих: запись.ничьих,
        партий: запись.партий,
        деньБотов: запись.деньБотов,
        очкиОтБотовЗаДень: запись.очкиОтБотовЗаДень,
        последняяИгра: запись.последняяИгра
      });
    }
  }
  try {
    fs.mkdirSync(папка(), { recursive: true });
    // Во временный файл и переименование: обрывка на диске не бывает.
    fs.writeFileSync(файлПокаПишем(), JSON.stringify({ игроки: список }), 'utf8');
    fs.renameSync(файлПокаПишем(), файл());
  } catch (сбой) {
    /* Не записалось — память останется до следующей попытки. */
  }
}

/** Пометить, что память изменилась. Настоящая запись — чуть погодя. */
function записатьПогодя() {
  if (!записьРазрешена) return;
  естьЧтоЗаписать = true;
  if (таймерЗаписи !== null) return;
  таймерЗаписи = setTimeout(function () {
    таймерЗаписи = null;
    if (естьЧтоЗаписать) записатьСейчас();
  }, ЖДЁМ_ПЕРЕД_ЗАПИСЬЮ);
  if (таймерЗаписи.unref) таймерЗаписи.unref();
}

/** Записать прямо сейчас (нужно при остановке сервера). */
function дописать() {
  if (таймерЗаписи !== null) {
    clearTimeout(таймерЗаписи);
    таймерЗаписи = null;
  }
  if (естьЧтоЗаписать) записатьСейчас();
  // Силу дописываем тем же движением: сервер останавливают один раз.
  сила.дописать();
}

/** Забыть тех, кто давно не играл. */
function прибраться() {
  const край = new Date();
  край.setDate(край.getDate() - ХРАНИМ_ДНЕЙ);
  const самыйСтарый = ключДня(край.getTime());
  for (const таблица of таблицы.values()) {
    for (const [номер, запись] of таблица) {
      if (запись.последняяИгра && запись.последняяИгра < самыйСтарый) {
        таблица.delete(номер);
      }
    }
  }
}

/* ---------------------------------------------------------------------
   Счёт
   --------------------------------------------------------------------- */

/** Сколько стоит победа над этим соперником. */
function ценаСоперника(соперник) {
  if (!соперник || !соперник.этоБот) return ЦЕНА_ПОБЕДЫ.человек;
  const цена = ЦЕНА_ПОБЕДЫ[соперник.уровень];
  return цена === undefined ? ЦЕНА_НЕИЗВЕСТНОГО_БОТА : цена;
}

/** Запись игрока в таблице этой игры; заводим по первой партии. */
function записьИгрока(игра, номер) {
  const таблица = таблицаИгры(игра);
  if (!таблица.has(номер)) таблица.set(номер, пустаяЗапись(номер));
  return таблица.get(номер);
}

/**
 * Добавить очки с оглядкой на дневной потолок для ботов.
 * Отвечает, сколько добавилось на самом деле.
 */
function начислить(запись, откуда, сколько, сегодня) {
  if (сколько <= 0) return 0;
  if (откуда === 'человек') {
    запись.очки += сколько;
    return сколько;
  }
  if (запись.деньБотов !== сегодня) {
    запись.деньБотов = сегодня;
    запись.очкиОтБотовЗаДень = 0;
  }
  const осталось = Math.max(0, ПОТОЛОК_ОТ_БОТОВ_В_СУТКИ - запись.очкиОтБотовЗаДень);
  const дадим = Math.min(сколько, осталось);
  запись.очкиОтБотовЗаДень += дадим;
  запись.очки += дадим;
  return дадим;
}

/**
 * Записать итог партии.
 *
 * Что приходит: имя игры и список сидевших за столом. Каждый — это
 * { номер, имя, этоБот, уровень, победил, ничья }. Номер есть только
 * у тех, кто играет из Telegram; остальных просто не считаем — опознать
 * их нечем, а выдумывать игрока ради строчки в таблице нельзя.
 *
 * Очки начисляются за КАЖДОГО обыгранного за столом: победа над тремя
 * людьми в компании и правда стоит втрое дороже победы над одним.
 */
function учестьПартию(игра, застольем) {
  if (!ужеЗагрузили) загрузить();
  if (!Array.isArray(застольем) || застольем.length < 2) return;

  /* Та же партия идёт и во вторую меру — силу. Зовём её отсюда, а не из
     комнат, чтобы у конца партии осталась ровно одна дверь: забыть одну
     из двух мер при следующей игре тогда просто негде. Своя память,
     свои правила и свой файл у силы отдельные. */
  сила.учесть(игра, застольем);

  const сегодня = ключДня();
  let менялось = false;

  for (const игрок of застольем) {
    if (!игрок || игрок.этоБот || !этоНомерИгрока(игрок.номер)) continue;

    const запись = записьИгрока(игра, игрок.номер);
    if (типИмени(игрок.имя)) запись.имя = типИмени(игрок.имя);
    запись.партий++;
    запись.последняяИгра = сегодня;
    менялось = true;

    if (игрок.ничья) {
      запись.ничьих++;
      /* Ничья — половина веса, и та же оглядка на потолок ботов.
         Половину округляем ВВЕРХ, а не вниз. Раньше было вниз, и ничья
         с лёгким ботом (цена 1) давала ноль: правило обещало половину,
         а человек получал пусто — из таких мелочей растёт недоверие ко
         всему числу. Очки у нас целые (дробные пришлось бы показывать
         как «1.5», а это уже про экран), поэтому из двух целых — 0 и 1 —
         берём то, которое обещание сдерживает. */
      for (const другой of застольем) {
        if (другой === игрок) continue;
        const половина = Math.ceil(ценаСоперника(другой) / 2);
        начислить(запись, другой && другой.этоБот ? 'бот' : 'человек', половина, сегодня);
      }
      continue;
    }
    if (!игрок.победил) continue;

    запись.побед++;
    for (const другой of застольем) {
      if (другой === игрок) continue;
      начислить(запись, другой && другой.этоБот ? 'бот' : 'человек',
                ценаСоперника(другой), сегодня);
    }
  }

  if (менялось) записатьПогодя();
}

/** Имя как строка разумной длины — или пусто. */
function типИмени(имя) {
  if (typeof имя !== 'string') return '';
  const чистое = имя.trim();
  return чистое ? чистое.slice(0, 40) : '';
}

/* ---------------------------------------------------------------------
   Что видит игрок
   --------------------------------------------------------------------- */

/** Вся таблица игры по порядку: больше очков — выше. */
function порядок(игра) {
  if (!ужеЗагрузили) загрузить();
  const все = Array.from(таблицаИгры(игра).values());
  все.sort(function (а, б) {
    if (б.очки !== а.очки) return б.очки - а.очки;
    if (б.побед !== а.побед) return б.побед - а.побед;
    // Совсем поровну — раньше тот, кто играл недавно: таблица живее.
    return String(б.последняяИгра).localeCompare(String(а.последняяИгра));
  });
  return все;
}

/**
 * Одна строка таблицы наружу. Собирается вручную, поле за полем:
 * номер Telegram остаётся здесь и наружу не уходит никогда.
 */
function строка(запись, место, этоЯ) {
  return {
    место: место,
    имя: запись.имя || 'Игрок',
    очки: запись.очки,
    побед: запись.побед,
    партий: запись.партий,
    этоЯ: этоЯ === true
  };
}

/**
 * Срез таблицы для этого игрока: верхушка, окно вокруг него и он сам.
 * Номер спрашивающего берётся из проверенной подписи — сюда приходит
 * уже готовое число, самой подписи этот файл не видит.
 */
function срезДляИгрока(игра, номер) {
  const все = порядок(игра);
  const моёМесто = все.findIndex(function (запись) { return запись.номер === номер; });

  const верхушка = все.slice(0, ВЕРХУШКИ).map(function (запись, номерВСписке) {
    return строка(запись, номерВСписке + 1, запись.номер === номер);
  });

  /* Вторая мера едет тем же ответом, отдельным полем. Собирает её
     server/сила-игроков.js — тоже вручную, поле за полем. */
  const сведенияОСиле = сила.срезДляИгрока(игра, номер);

  if (моёМесто === -1) {
    return {
      игра: игра,
      всего: все.length,
      яВТаблице: false,
      я: null,
      верхушка: верхушка,
      вокругМеня: [],
      сила: сведенияОСиле
    };
  }

  const начало = Math.max(0, моёМесто - СОСЕДЕЙ_СВЕРХУ);
  const конец = Math.min(все.length, моёМесто + СОСЕДЕЙ_СНИЗУ + 1);
  const вокруг = [];
  for (let место = начало; место < конец; место++) {
    вокруг.push(строка(все[место], место + 1, все[место].номер === номер));
  }

  return {
    игра: игра,
    всего: все.length,
    яВТаблице: true,
    я: строка(все[моёМесто], моёМесто + 1, true),
    верхушка: верхушка,
    вокругМеня: вокруг,
    сила: сведенияОСиле
  };
}

/** Сколько игроков в таблице — для проверок и сводок. */
function сколькоИгроков(игра) {
  if (!ужеЗагрузили) загрузить();
  return таблицаИгры(игра).size;
}

