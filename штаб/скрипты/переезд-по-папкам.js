// Переезд проекта по папкам игр, этап 2: js, css и шрифты уезжают из общей кучи
// в «игры/<игра>/» и «общее/…». Страницы (html) остаются в корне — адреса игр не меняются.
//
// Запуск:
//   node штаб/скрипты/переезд-по-папкам.js --сухо                 ничего не меняет, печатает план
//   node штаб/скрипты/переезд-по-папкам.js --корень=<копия> --без-git   переезд на копии проекта
//   node штаб/скрипты/переезд-по-папкам.js                        настоящий переезд (git mv) — запускает штаб
// Доводы:
//   --корень=<папка>   где лежит проект (по умолчанию — проект, в котором лежит программа)
//   --сухо             только посчитать и напечатать
//   --без-git          переносить обычным переименованием (для копии без .git)
//   --отчёт=<файл>     куда записать полный отчёт (json): таблица переезда, правки, список «руками»
//
// Как устроено. Программа сначала ВСЁ считает в памяти (таблицу «старый путь → новый путь»
// и новый текст каждого файла), потом проверяет воображаемый результат той же проверкой
// tests/подключения-не-в-пустоту.js и только после зелёного прогноза трогает диск.
// Замены делаются только по таблице ИМЁН файлов (имена уникальны). Где программа видит
// старую папку, но не уверена (перечисление папки, регулярка, путь из переменных), —
// она ничего не правит и пишет место в отчёт «руками».
// Повторный запуск на уже переехавшем проекте ничего не меняет.

