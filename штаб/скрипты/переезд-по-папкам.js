/** Собирает образцы поиска имён один раз. */
function образцыИмён(таблица) {
  const имена = [...таблица.keys()].sort((а, б) => б.length - а.length);
  const основы = имена.filter((и) => и.endsWith('.js')).map((и) => и.slice(0, -3));
  return {
    // полное имя с окончанием ЛИБО имя скрипта без «.js» сразу после слэша и перед кавычкой: require('../js/языки')
    имя: new RegExp(
      '(?<![\\p{L}\\p{N}_-])(' + имена.map(дляРегулярки).join('|') + ')(?![\\p{L}\\p{N}_-]|\\.[a-z])'
      // …и то же после звена 'js' в path.join: require(path.join(КОРЕНЬ, 'js', 'домино-правила'))
      + '|(?<=\\/|[\'"`]js[\'"`]\\s*,\\s*[\'"`])(' + основы.map(дляРегулярки).join('|') + ')(?=[\'"`])', 'gu'),
    // имя, записанное внутри регулярки: style\.css
    вРегулярке: new RegExp('(?<![\\p{L}\\p{N}_-])(' + имена.map((и) => дляРегулярки(и).replace(/\\\./g, '\\\\\\.')).join('|') + ')', 'gu'),
  };
}

/**
 * Правит ссылки в коде и страницах: html, js, server, bot, штаб, tests, rules.
 * файл: { путь (где он будет лежать), группа, сейчас (где лежит сейчас), переезжает }.
 * Возвращает новый текст, число замен и список мест «руками».
 */
function правитьКод(текст, файл, таблица, образцы) {
  const замены = []; // { от, до, на }
  const руками = [];
  let ужеНовое = 0;
  const вРуки = (место, вид) => руками.push({ файл: файл.путь, строка: номерСтроки(текст, место), вид, текст: строкаЦеликом(текст, место).trim().slice(0, 200) });
  const свояПапкаСейчас = папкаПути(файл.сейчас);
  const свояПапкаПотом = папкаПути(файл.путь);
  const скриптЕдет = файл.группа === 'js' && файл.переезжает;

  for (const м of текст.matchAll(образцы.имя)) {
    const место = м.index;
    const найдено = м[0];
    const имя = м[1] || м[2] + '.js';
    const з = таблица.get(имя);
    const старыйКаталог = папкаПути(з.старый); // 'js', 'шрифты' или '' (корень)
    const новыйПуть = з.новаяПапка + '/' + найдено; // без «.js», если его не было
    const до = текст.slice(Math.max(0, место - 240), место);
    const перед = до.slice(-1);
    const кавычкаПеред = перед === '\'' || перед === '"' || перед === '`';
    const конец = место + найдено.length;

    // Уже новый путь — повторный запуск ничего не трогает.
    if (до.endsWith(з.новаяПапка + '/')) { ужеНовое++; continue; }
    const новыеЗвенья = з.новаяПапка.split('/').map((с) => '[\'"`]' + дляРегулярки(с) + '[\'"`]\\s*,\\s*').join('');
    if (new RegExp(новыеЗвенья + '[\'"`]$', 'u').test(до)) { ужеНовое++; continue; }

    if (старыйКаталог) {
      const сКаталогом = до.endsWith(старыйКаталог + '/');
      const знакДоКаталога = до.slice(-старыйКаталог.length - 2, -старыйКаталог.length - 1);
      if (сКаталогом && !ЗНАК_ИМЕНИ.test(знакДоКаталога)) {
        // Написание «…js/имя.js». У переезжающего скрипта «../js/имя» в require и new URL считается
        // от самого скрипта — пересчитываем целиком; во всех остальных случаях то, что стоит перед
        // «js/», указывает на корень проекта и остаётся как есть.
        const хвост = до.match(/(['"`])((?:\.\.?\/)+)[^'"`\s]*$/u);
        const отСкрипта = файл.группа === 'js' && хвост && хвост[2].startsWith('../') && /require\(|new URL\(/.test(строкаЦеликом(текст, место));
        if (отСкрипта) {
          if (!скриптЕдет) { ужеНовое++; continue; }
          const начало = место - (до.length - до.lastIndexOf(хвост[1]) - 1);
          замены.push({ от: начало, до: конец, на: относительно(свояПапкаПотом, новыйПуть) });
        } else {
          замены.push({ от: место - старыйКаталог.length - 1, до: конец, на: новыйПуть });
        }
        continue;
      }
      // Написание path.join(…, 'js', 'имя.js'): звено 'js' меняем на звенья новой папки.
      const звено = до.match(new RegExp('([\'"`])' + дляРегулярки(старыйКаталог) + '\\1(\\s*,\\s*)([\'"`])$', 'u'));
      if (звено) {
        const к = звено[1];
        замены.push({ от: место - звено[0].length, до: место, на: з.новаяПапка.split('/').map((с) => к + с + к).join(звено[2]) + звено[2] + звено[3] });
        continue;
      }
      // Соседний файл у скрипта: require('./имя.js') — папки соседей теперь могут быть разными.
      if (файл.группа === 'js' && до.endsWith('./') && /['"`]$/.test(до.slice(0, -2))) {
        if (!скриптЕдет) { ужеНовое++; continue; }
        замены.push({ от: место - 2, до: конец, на: относительно(свояПапкаПотом, новыйПуть) });
        continue;
      }
      if (кавычкаПеред && !вКомментарии(текст, место)) вРуки(место, 'имя файла в кавычках без папки (путь собирается из кусков)');
      continue; // простое упоминание в тексте — не трогаем
    }

    // Оформление из корня: «style-x.css» в кавычках или после слэша, ведущего в корень.
    if (кавычкаПеред) {
      // На странице и в браузерном скрипте путь считается от страницы в корне — меняем смело.
      // В проверках и программах так же часто пишут path.join(времПапка, 'style.css') — путь в КОПИИ
      // или просто слова для человека. Поэтому там меняем только то, что явно считается от корня проекта.
      const отСтраницы = файл.группа === 'html' || файл.группа === 'rules' || файл.группа === 'js';
      const отКорня = /(?:корень[\p{L}\p{N}_]*|проект[\p{L}\p{N}_]*|root\w*|__dirname\s*,\s*(['"`])\.\.\1)\s*,\s*['"`]$/iu.test(до);
      // В проверках путь от корня узнаём ещё по трём приметам: читают прямо по имени (папка запуска — корень),
      // зовут местную «путь(номер довода, 'имя')», либо имя стоит в списке путей рядом со страницей или «js/…».
      const отКорняВПроверке = файл.группа === 'tests' && (/(?:readFileSync\(|путь\(\d+,)\s*['"`]$/u.test(до) || вСпискеПутей(текст, место - 1));
      if (отСтраницы || отКорня || отКорняВПроверке) замены.push({ от: место, до: конец, на: новыйПуть });
      else if (!вКомментарии(текст, место)) вРуки(место, 'оформление в кавычках: от какой папки считается путь — неясно');
      continue;
    }
    if (перед === '/') {
      const кусок = до.match(/[^\s'"`()=<>,]*$/u)[0];
      if (/^((\.\.?\/)+|\/|\$\{[^}]*\}\/|https?:\/\/[^\/]+\/)$/u.test(кусок)) замены.push({ от: место, до: конец, на: новыйПуть });
      else if (!вКомментарии(текст, место)) вРуки(место, 'оформление после непонятной папки «' + кусок.slice(-40) + '»');
      continue;
    }
  }

  // Прочие относительные пути переезжающего скрипта (new URL('../img/…', АДРЕС_ФАЙЛА), require('../server/…')):
  // они считаются от скрипта, а скрипт уезжает на уровень глубже.
  if (скриптЕдет) {
    for (const м of текст.matchAll(/(['"`])((?:\.\.\/)+)([^'"`\s]*)\1/gu)) {
      const началоПути = м.index + 1;
      const конецПути = началоПути + м[2].length + м[3].length;
      if (замены.some((х) => началоПути < х.до && конецПути > х.от)) continue; // это имя из таблицы, уже пересчитано
      if (вКомментарии(текст, м.index)) continue;
      if (/require\(|new URL\(/.test(строкаЦеликом(текст, м.index))) {
        const цель = path.posix.normalize(path.posix.join(свояПапкаСейчас, м[2] + м[3]));
        const слэш = м[3] === '' || м[3].endsWith('/') ? '/' : '';
        замены.push({ от: началоПути, до: конецПути, на: path.posix.relative(свояПапкаПотом, цель || '.') + (path.posix.relative(свояПапкаПотом, цель || '.').endsWith('/') ? '' : слэш) });
      } else {
        вРуки(м.index, 'относительный путь в скрипте, который переезжает (от чего он считается — неясно)');
      }
    }
  }

  // Проверки: то, что берётся надёжным правилом, переводим на общий помощник tests/пути-проекта.js.
  if (файл.группа === 'tests') правилаПроверок(текст, файл, таблица, образцы, замены);

  // Места, где видна старая папка, но замена не очевидна, — только в отчёт.
  const занято = (место) => замены.some((х) => место >= х.от && место < х.до);
  const поискиРуками = [
    [/(?<![\p{L}\p{N}_.-])(?:(['"`])js\1|js\\?\/)/gu, 'папка js без известного имени файла (перечисление папки, регулярка или путь из переменных)', (м) => текст.slice(Math.max(0, м.index - 6), м.index) === 'общее/' || текст.slice(Math.max(0, м.index - 9), м.index).replace(/['"`,\s]/g, '').endsWith('общее')],
    [/(?<![\p{L}\p{N}_.-])(?:(['"`])шрифты\1|шрифты\\?\/)/gu, 'папка шрифты без известного имени файла', (м) => текст.slice(Math.max(0, м.index - 6), м.index) === 'общее/' || текст.slice(Math.max(0, м.index - 9), м.index).replace(/['"`,\s]/g, '').endsWith('общее')],
    [/style-?(?=['"`]\s*\+|\$\{)|style[^'"`\n]{0,24}\\\.css|\\\.css\$/gu, 'имя оформления собирается из кусков или ищется регуляркой', () => false],
    [образцы.вРегулярке, 'имя файла внутри регулярки', () => false],
  ];
  const ужеЗаписано = new Set();
  for (const [образец, вид, пропустить] of поискиРуками) {
    for (const м of текст.matchAll(образец)) {
      if (занято(м.index) || пропустить(м) || вКомментарии(текст, м.index)) continue;
      // чужой сайт (https://telegram.org/js/…) — не наша папка
      if (/:\/\/[^\s'"`]*$/u.test(текст.slice(Math.max(0, м.index - 120), м.index))) continue;
      // «js/» перед известным именем уже обработано выше
      const ключ = номерСтроки(текст, м.index) + '|' + вид;
      if (ужеЗаписано.has(ключ)) continue;
      ужеЗаписано.add(ключ);
      вРуки(м.index, вид);
    }
  }

  // Собираем новый текст: замены не пересекаются, идём с конца.
  замены.sort((а, б) => б.от - а.от);
  let новый = текст;
  let прошлая = Infinity;
  let сделано = 0;
  for (const х of замены) {
    if (х.до > прошлая) continue; // пересечение — оставляем первую замену
    if (новый.slice(х.от, х.до) !== х.на) { новый = новый.slice(0, х.от) + х.на + новый.slice(х.до); сделано++; }
    прошлая = х.от;
  }
  return { текст: новый, замен: сделано, руками, ужеНовое };
}

// ───────────────────────── Правила для проверок (tests/) ─────────────────────────

/** Имена папок проекта: по ним узнаём список папок для копирования (а не список окончаний файлов). */
const ПАПКИ_ПРОЕКТА = new Set(['server', 'js', 'img', 'шрифты', 'tests', 'rules', 'bot', 'штаб', 'эталон']);

/** Ближайшая незакрытая скобка слева от места: начало вызова или списка. */
function открывающая(текст, место) {
  let глубина = 0;
  for (let i = место - 1; i >= Math.max(0, место - 800); i--) {
    const с = текст[i];
    if (с === ')' || с === ']' || с === '}') глубина++;
    else if (с === '(' || с === '[' || с === '{') { if (глубина === 0) return i; глубина--; }
  }
  return -1;
}

/** Доводы вызова (или элементы списка) от открывающей скобки до её пары. Строки пропускает целиком. */
function доводыОт(текст, открытие) {
  const пара = { '(': ')', '[': ']', '{': '}' };
  const закрыть = пара[текст[открытие]];
  const доводы = [];
  const стек = [];
  let начало = открытие + 1;
  const обрезать = ([от, до]) => {
    while (от < до && /\s/.test(текст[от])) от++;
    while (до > от && /\s/.test(текст[до - 1])) до--;
    return { от, до, текст: текст.slice(от, до) };
  };
  for (let i = открытие + 1; i < Math.min(текст.length, открытие + 3000); i++) {
    const с = текст[i];
    if (с === '\'' || с === '"' || с === '`') {
      let j = i + 1;
      while (j < текст.length && текст[j] !== с) { if (текст[j] === '\\') j++; j++; }
      i = j;
      continue;
    }
    if (пара[с]) { стек.push(пара[с]); continue; }
    if (стек.length) { if (с === стек[стек.length - 1]) стек.pop(); continue; }
    if (с === ',') { доводы.push([начало, i]); начало = i + 1; continue; }
    if (с === закрыть) {
      if (текст.slice(начало, i).trim()) доводы.push([начало, i]);
      return { закрытие: i, доводы: доводы.map(обрезать) };
    }
    if (с === ')' || с === ']' || с === '}') return null;
  }
  return null;
}

/** Место стоит в списке путей от корня: рядом в том же списке есть страница или путь «папка/имя.js». */
function вСпискеПутей(текст, место) {
  const открытие = открывающая(текст, место);
  if (открытие < 0 || текст[открытие] !== '[') return false;
  const разбор = доводыОт(текст, открытие);
  return Boolean(разбор) && разбор.доводы.some((д) => /^(['"`])[^'"`]*(?:\.html|\/[^'"`\/]+\.js)\1$/u.test(д.текст));
}

/**
 * Правила для проверок. Добавляет замены в общий список:
 *   список папок ['server','js','img','шрифты']     → ['server', ...Пути.папкиКода(), 'img']
 *   fs.cpSync(path.join(А,'js'), path.join(Б,'js')) → Пути.скопироватьКод(А, Б, 'js')
 *   fs.mkdirSync(path.join(А,'js'), …)              → Пути.создатьПапкиКода(А)
 *   fs.readdirSync(path.join(А,'js'))               → Пути.всеJs(А)
 *   path.join(А,'js', перем)                        → Пути.путь(перем, А)
 *   'js/' + перем, `js/${перем}`                    → Пути.отКорня(перем)
 *   /src="js\/сеть\.js/                             → /src="общее\/js\/сеть\.js/
 *   /src="(js\/[^"]+)"/                             → /src="((?:общее|игры)\/[^"]+)"/
 * Замена того же текста на себя — знак «здесь править не надо, в „руками“ не писать».
 */
function правилаПроверок(текст, файл, таблица, образцы, замены) {
  const глубина = файл.путь.split('/').length - 2; // tests/а.js → 0, tests/папка/а.js → 1
  const Пути = 'require(\'' + (глубина > 0 ? '../'.repeat(глубина) : './') + 'пути-проекта.js\')';
  const занято = (от, до) => замены.some((х) => от < х.до && до > х.от);
  const добавить = (от, до, на) => { if (занято(от, до)) return false; замены.push({ от, до, на }); return true; };
  const неТрогать = (от, до) => добавить(от, до, текст.slice(от, до));
  const кореньИз = (доводы, вызов) => (доводы.length === 1 ? доводы[0].текст : (вызов || 'path.join') + '(' + текст.slice(доводы[0].от, доводы[доводы.length - 1].до) + ')');
  const вКавычках = (с) => { const м = с.match(/^(['"`])([^'"`]*)\1$/); return м ? м[2] : null; };

  /** Разбирает path.join(…, 'js'[, ещё]) вокруг места: возвращает части или null. */
  const разобратьJoin = (место, токен) => {
    const открытие = открывающая(текст, место);
    if (открытие < 0 || текст[открытие] !== '(') return null;
    // модуль path в проверках зовут по-разному (path, путь, p) — узнаём по «.join(» и «.resolve(»
    const мВызов = текст.slice(Math.max(0, открытие - 40), открытие).match(/[\p{L}_$][\p{L}\p{N}_$]*\.(?:join|resolve)$/u);
    if (!мВызов) return null;
    const имяВызова = мВызов[0];
    const разбор = доводыОт(текст, открытие);
    if (!разбор) return null;
    const к = разбор.доводы.findIndex((д) => д.от === место);
    if (к < 1 || вКавычках(разбор.доводы[к].текст) !== токен) return null;
    const перед = разбор.доводы.slice(0, к);
    return { имяВызова, начало: открытие - имяВызова.length, конец: разбор.закрытие + 1, перед, после: разбор.доводы.slice(к + 1), ужеНовое: вКавычках(перед[перед.length - 1].текст) === 'общее' };
  };

  for (const м of текст.matchAll(/(['"`])(js|шрифты)\1/gu)) {
    const место = м.index;
    const токен = м[2];
    if (вКомментарии(текст, место)) continue;
    const открытие = открывающая(текст, место);
    if (открытие < 0) continue;

    // Список папок для копирования.
    if (текст[открытие] === '[') {
      const разбор = доводыОт(текст, открытие);
      if (!разбор || !разбор.доводы.length) continue;
      const имена = разбор.доводы.map((д) => вКавычках(д.текст));
      if (имена.some((и) => и === null)) continue;
      if (!имена.some((и) => и !== токен && ПАПКИ_ПРОЕКТА.has(и))) continue; // похоже на список окончаний, не папок
      const естьJs = имена.includes('js');
      const новые = [];
      разбор.доводы.forEach((д, i) => {
        if (имена[i] === 'js') новые.push('...' + Пути + '.папкиКода()');
        else if (имена[i] === 'шрифты') { if (!естьJs) новые.push('...' + Пути + '.папкиКода(\'шрифты\')'); }
        else новые.push(д.текст);
      });
      добавить(разбор.доводы[0].от, разбор.доводы[разбор.доводы.length - 1].до, новые.join(', '));
      continue;
    }

    const вызов = разобратьJoin(место, токен);
    if (!вызов) continue;
    if (вызов.ужеНовое) { неТрогать(место, место + м[0].length); continue; }
    const корень = кореньИз(вызов.перед, вызов.имяВызова);

    // path.join(А, 'js', перем) — место файла по имени из переменной или из выражения ('языки-' + игра + '.js').
    if (вызов.после.length === 1 && вКавычках(вызов.после[0].текст) === null) {
      добавить(вызов.начало, вызов.конец, Пути + '.путь(' + вызов.после[0].текст + ', ' + корень + ')');
      continue;
    }
    if (вызов.после.length !== 0) continue;

    // path.join(А, 'js') — сама папка: смотрим, что с ней делают.
    const снаружи = текст.slice(Math.max(0, вызов.начало - 40), вызов.начало).match(/fs\.(mkdirSync|readdirSync|cpSync)\(\s*$/);
    if (!снаружи) continue;
    const началоВнешнего = вызов.начало - снаружи[0].length;
    const внешний = доводыОт(текст, началоВнешнего + снаружи[0].indexOf('('));
    if (!внешний || внешний.доводы[0].от !== вызов.начало) continue;
    const конецВнешнего = внешний.закрытие + 1;
    if (снаружи[1] === 'mkdirSync') {
      добавить(началоВнешнего, конецВнешнего, Пути + '.создатьПапкиКода(' + корень + ')');
    } else if (снаружи[1] === 'readdirSync' && токен === 'js' && внешний.доводы.length === 1) {
      добавить(началоВнешнего, конецВнешнего, Пути + '.всеJs(' + корень + ')');
    } else if (снаружи[1] === 'cpSync' && внешний.доводы.length >= 2) {
      // второй довод обязан быть такой же папкой в другом корне
      const второй = внешний.доводы[1];
      const местоВторого = текст.slice(второй.от, второй.до).search(new RegExp('([\'"`])' + токен + '\\1\\s*\\)$', 'u'));
      const куда = местоВторого < 0 ? null : разобратьJoin(второй.от + местоВторого, токен);
      if (куда && куда.после.length === 0 && куда.начало === второй.от && куда.конец === второй.до) {
        добавить(началоВнешнего, конецВнешнего, Пути + '.скопироватьКод(' + корень + ', ' + кореньИз(куда.перед, куда.имяВызова) + ', \'' + токен + '\')');
      }
    }
  }

  // Папка js, положенная в переменную: const ПАПКА_JS = … path.join(А, 'js');
  // Дальше по файлу path.join(ПАПКА_JS, имя) → Пути.вПапке(ПАПКА_JS, имя): если файл лежит прямо в папке
  // (своя копия из довода) — вернётся он же, поведение не меняется; если папки js уже нет — место по имени.
  for (const м of текст.matchAll(/(?:const|let|var)\s+([\p{L}_$][\p{L}\p{N}_$]*)\s*=[^;\n]*(['"`])js\2\s*\)\s*;/gu)) {
    if (вКомментарии(текст, м.index)) continue;
    const имя = м[1];
    for (const м2 of текст.matchAll(new RegExp('(?<![\\p{L}\\p{N}_$.])path\\.join\\(\\s*' + дляРегулярки(имя) + '\\s*,', 'gu'))) {
      const разбор = доводыОт(текст, м2.index + 'path.join'.length);
      if (!разбор || разбор.доводы.length !== 2 || вКомментарии(текст, м2.index)) continue;
      добавить(м2.index, разбор.закрытие + 1, Пути + '.вПапке(' + имя + ', ' + разбор.доводы[1].текст + ')');
    }
    for (const м2 of текст.matchAll(new RegExp('fs\\.readdirSync\\(\\s*' + дляРегулярки(имя) + '\\s*\\)', 'gu'))) {
      if (!вКомментарии(текст, м2.index)) добавить(м2.index, м2.index + м2[0].length, Пути + '.всеJsВПапке(' + имя + ')');
    }
  }

  // Сосед по папке, которого просят прочитать: require(path.join(path.dirname(файл), 'языки.js')).
  // Только чтение (require): место, КУДА пишут копию, этим правилом не трогаем.
  for (const м of текст.matchAll(/require\(path\.join\(path\.dirname\(([^()]+)\),\s*(['"`])([^'"`]+)\2\)/gu)) {
    if (вКомментарии(текст, м.index) || !(таблица.has(м[3]) || таблица.has(м[3] + '.js'))) continue;
    добавить(м.index + 'require('.length, м.index + м[0].length, Пути + '.рядомИлиВПроекте(' + м[1].trim() + ', ' + м[2] + м[3] + м[2] + ')');
  }

  // 'js/' + перем,  '/js/' + перем,  'src="js/' + перем
  for (const м of текст.matchAll(/(['"`])((?:[^'"`\n]*[="\/'(\s])?)js\/\1\s*\+\s*([\p{L}_$][\p{L}\p{N}_$.]*)/gu)) {
    if (вКомментарии(текст, м.index)) continue;
    const конец = м.index + м[0].length;
    // подпись для vm (filename) — только слова в сообщении об ошибке, путь по ней никто не ищет
    if (/filename:\s*$/.test(текст.slice(Math.max(0, м.index - 20), м.index))) { неТрогать(м.index, конец); continue; }
    if (текст[конец] === '(' || текст[конец] === '[') continue; // вызов или индекс — выражение длиннее, чем мы видим
    if (/:\/\//.test(м[2])) continue; // чужой сайт
    добавить(м.index, конец, (м[2] ? м[1] + м[2] + м[1] + ' + ' : '') + Пути + '.отКорня(' + м[3] + ')');
  }
  // `…js/${перем}…`
  for (const м of текст.matchAll(/(?<![\p{L}\p{N}_.-])js\/\$\{([^{}`]+)\}/gu)) {
    if (вКомментарии(текст, м.index)) continue;
    добавить(м.index, м.index + м[0].length, '${' + Пути + '.отКорня(' + м[1] + ')}');
  }

  // Имя файла внутри регулярки.
  for (const м of текст.matchAll(образцы.вРегулярке)) {
    const з = таблица.get(м[1].replace(/\\\./g, '.'));
    if (!з || вКомментарии(текст, м.index)) continue;
    const конец = м.index + м[0].length;
    const до = текст.slice(Math.max(0, м.index - 80), м.index);
    const новаяПапка = з.новаяПапка.replace(/\//g, '\\/') + '\\/';
    const стараяПапка = папкаПути(з.старый);
    if (до.endsWith(новаяПапка)) { неТрогать(м.index, конец); continue; }
    if (стараяПапка && до.endsWith(стараяПапка + '\\/') && !ЗНАК_ИМЕНИ.test(до.slice(-стараяПапка.length - 3, -стараяПапка.length - 2))) {
      добавить(м.index - стараяПапка.length - 2, конец, новаяПапка + м[0]);
      continue;
    }
    // href="style\.css — адрес на странице считается от корня
    if (!стараяПапка && /(?:src|href)=["']$/.test(до)) { добавить(м.index, конец, новаяПапка + м[0]); continue; }
    // «\/style\.css» — ищут хвост адреса: он совпадёт и с новым адресом «/общее/css/style.css»
    if (до.endsWith('\\/')) { неТрогать(м.index, конец); continue; }
  }
  // Регулярка «любой скрипт страницы»: src="(js\/[^"]+)"
  // …и src="js\/([^"]+)\.js" — тут в скобки берут одно имя, папку игры пропускаем отдельно
  for (const м of текст.matchAll(/(?<![\p{L}\p{N}_.-])js\\\/(\(?)(?=\[\^)/gu)) {
    if (вКомментарии(текст, м.index) || текст.slice(Math.max(0, м.index - 7), м.index) === 'общее\\/') continue;
    добавить(м.index, м.index + м[0].length, м[1] ? '(?:общее|игры)\\/[^"\'\\/]+\\/(' : '(?:общее|игры)\\/');
  }
}

/**
 * Заплатки: то, что правилом не берётся. Файл штаб/скрипты/переезд-заплатки.json —
 * список записей { файл, было, стало } с точным текстом. Применяются последним шагом.
 * «Было» обязано найтись ровно один раз — иначе программа падает, чтобы заплатка не протухла молча.
 * Если «было» нет, а «стало» уже стоит — заплатка считается применённой (повторный запуск).
 */
function применитьЗаплатки(читатьТекст) {
  const файлЗаплаток = path.join(__dirname, 'переезд-заплатки.json');
  const итог = { всего: 0, применено: 0, ужеСтояли: 0, тексты: new Map() };
  if (!fs.existsSync(файлЗаплаток)) return итог;
  const заплатки = JSON.parse(fs.readFileSync(файлЗаплаток, 'utf8'));
  const беды = [];
  заплатки.forEach((з, номер) => {
    итог.всего++;
    const кто = 'заплатка №' + (номер + 1) + ' (' + з.файл + ')';
    if (!з.файл || typeof з.было !== 'string' || typeof з.стало !== 'string' || !з.было || з.было === з.стало) { беды.push(кто + ': нужны поля файл, было, стало, и «было» не равно «стало»'); return; }
    if (!итог.тексты.has(з.файл) && !естьНаДиске(з.файл)) { беды.push(кто + ': нет такого файла'); return; }
    const текст = итог.тексты.has(з.файл) ? итог.тексты.get(з.файл) : читатьТекст(з.файл);
    // окончания строк в файле могут быть \r\n — заплатки пишутся с \n
    const было = текст.includes('\r\n') ? з.было.replace(/\r?\n/g, '\r\n') : з.было;
    const стало = текст.includes('\r\n') ? з.стало.replace(/\r?\n/g, '\r\n') : з.стало;
    const сколько = текст.split(было).length - 1;
    const стоит = текст.includes(стало);
    if (стоит && (сколько === 0 || стало.includes(было))) { итог.ужеСтояли++; return; }
    if (сколько !== 1) { беды.push(кто + ': «было» найдено ' + сколько + ' раз(а), а должно ровно один: ' + JSON.stringify(з.было.slice(0, 90))); return; }
    итог.тексты.set(з.файл, текст.replace(было, () => стало));
    итог.применено++;
  });
  if (беды.length) упасть('заплатки не сошлись с текстом файлов (диск не тронут):\n  ' + беды.join('\n  '));
  return итог;
}

/**
 * Правит url() и @import в css: css считает путь от себя, поэтому каждый путь
 * пересчитывается от НОВОГО места файла.
 */
function правитьОформление(текст, файл, таблица, старыеПути) {
  const руками = [];
  const папкаСтарая = папкаПути(файл.старый);
  const папкаНовая = папкаПути(файл.путь);
  let замен = 0;
  // комментарии закрашиваем только для поиска, текст правим настоящий
  const безКомментариев = текст.replace(/\/\*[\s\S]*?\*\//g, (к) => к.replace(/[^\n]/g, ' '));
  const образец = /url\(\s*(["']?)([^"')]*)\1\s*\)|@import\s+(["'])([^"']*)\3/gi;
  const правки = [];
  let м;
  while ((м = образец.exec(безКомментариев))) {
    const адрес = м[2] !== undefined ? м[2] : м[4];
    const чистый = адрес.trim();
    if (!чистый || /^(https?:|\/\/|data:|blob:|#|%23)/i.test(чистый) || чистый.includes('${')) continue;
    const хвост = (чистый.match(/[?#].*$/) || [''])[0];
    const дорога = хвост ? чистый.slice(0, -хвост.length) : чистый;
    let раскрытая = дорога;
    try { раскрытая = decodeURIComponent(дорога); } catch (e) { /* как есть */ }
    const отКорня = дорога.startsWith('/');
    // 1) считаем путь от СТАРОГО места файла и переводим цель по таблице
    let цель = отКорня ? path.posix.normalize(раскрытая.slice(1)) : path.posix.normalize(path.posix.join(папкаСтарая, раскрытая));
    const запись = старыеПути.get(цель);
    if (запись) цель = запись.новый;
    const цельЕсть = Boolean(запись) || (!цель.startsWith('..') && естьНаДиске(цель));
    const местоАдреса = м.index + м[0].indexOf(адрес);
    if (цельЕсть) {
      const новыйАдрес = (отКорня ? '/' + цель : path.posix.relative(папкаНовая, цель)) + хвост;
      // кириллицу и пробелы пишем так же, как было: если исходный путь был закодирован — кодируем
      const итоговый = раскрытая !== дорога ? encodeURI(новыйАдрес) : новыйАдрес;
      if (итоговый !== чистый) правки.push({ от: местоАдреса, до: местоАдреса + адрес.length, на: итоговый });
      continue;
    }
    // 2) может, путь уже пересчитан (повторный запуск): тогда он верен от нового места
    const отНового = path.posix.normalize(path.posix.join(папкаНовая, раскрытая));
    const уже = [...таблица.values()].some((з) => з.новый === отНового) || (!отНового.startsWith('..') && естьНаДиске(отНового));
    if (!уже) руками.push({ файл: файл.путь, строка: номерСтроки(текст, м.index), вид: 'url() или @import ведёт в пустоту ещё до переезда', текст: м[0].slice(0, 200) });
  }
  правки.sort((а, б) => б.от - а.от);
  let новый = текст;
  for (const х of правки) { новый = новый.slice(0, х.от) + х.на + новый.slice(х.до); замен++; }
  return { текст: новый, замен, руками, ужеНовое: 0 };
}

// ───────────────────────── Воображаемый диск (для прогноза) ─────────────────────────

/** Диск, каким он станет после переезда: переносы и новые тексты наложены на настоящий. */
function воображаемыйДиск(переносы, новыеТексты, остаютсяНаСтаром) {
  const настоящий = дискПроекта(КОРЕНЬ);
  const ушли = new Set();
  const откуда = new Map(); // новый путь → старый
  for (const [старый, новый] of переносы) { откуда.set(новый, старый); if (!остаютсяНаСтаром.has(старый)) ушли.add(старый); }
  return {
    есть: (п) => откуда.has(п) || (!ушли.has(п) && настоящий.есть(п)),
    читать: (п) => (новыеТексты.has(п) ? новыеТексты.get(п) : настоящий.читать(откуда.get(п) || п)),
    список: (папка) => {
      const итог = new Map();
      for (const з of настоящий.список(папка)) {
        const путь = папка ? папка + '/' + з.имя : з.имя;
        if (!з.папка && ушли.has(путь)) continue;
        итог.set(з.имя, з);
      }
      const начало = папка ? папка + '/' : '';
      for (const новый of откуда.keys()) {
        if (!новый.startsWith(начало)) continue;
        const остаток = новый.slice(начало.length);
        const имя = остаток.split('/')[0];
        if (!итог.has(имя)) итог.set(имя, { имя, папка: остаток.includes('/') });
      }
      return [...итог.values()];
    },
  };
}

