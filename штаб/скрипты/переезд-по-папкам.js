/** Файлы папки (пути от корня). Вглубь — только если попросили. */
function файлыПапки(папка, подходит, вглубь) {
  const найдено = [];
  if (!естьНаДиске(папка || '.')) return найдено;
  for (const з of fs.readdirSync(полный(папка || '.'), { withFileTypes: true })) {
    const путь = папка ? папка + '/' + з.name : з.name;
    if (з.isDirectory()) {
      if (вглубь && !ПРОПУСКАТЬ_ПАПКИ.has(з.name)) найдено.push(...файлыПапки(путь, подходит, true));
    } else if (з.isFile() && подходит.test(з.name)) {
      найдено.push(путь);
    }
  }
  return найдено;
}

function номерСтроки(текст, место) {
  let н = 1;
  for (let i = 0; i < место; i++) if (текст.charCodeAt(i) === 10) н++;
  return н;
}

function строкаЦеликом(текст, место) {
  const начало = текст.lastIndexOf('\n', место - 1) + 1;
  let конец = текст.indexOf('\n', место);
  if (конец < 0) конец = текст.length;
  return текст.slice(начало, конец);
}

/** Место стоит в комментарии? Грубо, по началу строки и по «//» перед местом. */
function вКомментарии(текст, место) {
  const начало = текст.lastIndexOf('\n', место - 1) + 1;
  const до = текст.slice(начало, место);
  return /^\s*(\/\/|\/?\*|<!--|#)/.test(до) || /(^|[^:'"`\\])\/\/\s/.test(до);
}

/** Относительный путь из папки «откуда» к файлу «куда» — так, как его ждёт require. */
function относительно(откуда, куда) {
  const п = path.posix.relative(откуда || '.', куда);
  return п.startsWith('.') ? п : './' + п;
}

