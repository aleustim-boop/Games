/** Что переезжает: всё из js/, все css из корня, всё из шрифты/. Плюс то, что уже переехало (повторный запуск). */
function собратьФайлы() {
  const записи = new Map(); // имя → { имя, вид, старый, сейчас }
  const добавить = (путь, вид, старый) => {
    const имя = имяИзПути(путь);
    const было = записи.get(имя);
    if (!было) { записи.set(имя, { имя, вид, старый, сейчас: путь }); return; }
    // Один и тот же файл на старом и на новом месте разрешён только для оставленной копии.
    const одинИТотЖе = было.старый === старый;
    if (одинИТотЖе && имя === ОСТАВИТЬ_КОПИЮ) {
      было.копияНаСтаромМесте = true;
      if (путь !== старый) было.сейчас = путь; // рабочим считаем файл на новом месте
      return;
    }
    упасть(`двойник имени «${имя}»: ${было.сейчас} и ${путь}. Имена переезжающих файлов обязаны быть уникальны.`);
  };
  for (const п of файлыПапки('js', /\.js$/, false)) добавить(п, 'js', п);
  for (const п of файлыПапки('', /\.css$/, false)) добавить(п, 'css', п);
  for (const п of файлыПапки('шрифты', /./, false)) добавить(п, 'шрифт', п);
  // Уже переехавшее: старое место восстанавливаем по виду файла.
  for (const п of [...файлыПапки('общее', /./, true), ...файлыПапки('игры', /./, true)]) {
    const имя = имяИзПути(п);
    if (п.startsWith('общее/шрифты/')) добавить(п, 'шрифт', 'шрифты/' + имя);
    else if (имя.endsWith('.js')) добавить(п, 'js', 'js/' + имя);
    else if (имя.endsWith('.css')) добавить(п, 'css', имя);
  }
  return записи;
}

/** Какие страницы подключают файл: читаем теги script src и link href, сверяем по имени файла. */
function подключенияСтраниц(страницы) {
  const кто = new Map(); // имя файла → Set страниц
  for (const страница of страницы) {
    const текст = прочитать(страница).replace(/<!--[\s\S]*?-->/g, '');
    const теги = /<(?:script|link)\b[^>]*?\s(?:src|href)\s*=\s*(["'])([^"']*)\1/gi;
    let м;
    while ((м = теги.exec(текст))) {
      const адрес = м[2].split('#')[0].split('?')[0];
      if (!адрес || /^(https?:|\/\/|data:)/i.test(адрес)) continue;
      const имя = имяИзПути(адрес);
      if (!кто.has(имя)) кто.set(имя, new Set());
      кто.get(имя).add(страница);
    }
  }
  return кто;
}

/** Игра по приставке имени: «style-катан-стол.css» → «катан», «game-mines.js» → «mines». */
function играПоИмени(имя, игры) {
  const суть = имя.replace(ПРИСТАВКИ_ИМЁН, '');
  let лучшая = null;
  for (const игра of игры) {
    const подходит = суть === игра + '.js' || суть === игра + '.css' || суть.startsWith(игра + '-') || суть.startsWith(игра + '.');
    if (подходит && (!лучшая || игра.length > лучшая.length)) лучшая = игра;
  }
  return лучшая;
}

function построитьТаблицу(записи, страницы, тексты) {
  const игры = страницы.map((с) => ИГРА_СТРАНИЦЫ[с] || с.replace(/\.html$/, ''));
  const кто = подключенияСтраниц(страницы);

  // Кто, кроме страниц, упоминает файл: @import в css и любые упоминания имени в коде.
  const имена = [...записи.keys()].sort((а, б) => б.length - а.length);
  const образец = new RegExp('(?<![\\p{L}\\p{N}_-])(?:' + имена.map(дляРегулярки).join('|') + ')(?![\\p{L}\\p{N}_-])', 'gu');
  const основы = имена.filter((и) => и.endsWith('.js')).map((и) => и.slice(0, -3));
  const образецОснов = new RegExp('\\/(' + основы.map(дляРегулярки).join('|') + ')(?=[\'"`])', 'gu');
  const упоминают = new Map(); // имя → Set групп
  const отметить = (имя, группа) => { if (!упоминают.has(имя)) упоминают.set(имя, new Set()); упоминают.get(имя).add(группа); };
  for (const [путь, запись] of тексты) {
    if (запись.группа === 'html' || запись.группа === 'rules') continue;
    const свой = имяИзПути(путь);
    for (const м of запись.текст.matchAll(образец)) if (м[0] !== свой || запись.группа === 'tests') отметить(м[0], запись.группа);
    for (const м of запись.текст.matchAll(образецОснов)) отметить(м[1] + '.js', запись.группа);
  }

  const итог = { игры, индексныеВДурака: [], сироты: [], безСтраницНоНужны: [] };
  for (const з of записи.values()) {
    const страницыФайла = [...(кто.get(з.имя) || [])];
    const группы = [...(упоминают.get(з.имя) || [])];
    з.страницы = страницыФайла;
    з.упоминают = группы;
    let папка;
    let почему;
    if (з.вид === 'шрифт') { папка = 'общее/шрифты'; почему = 'шрифт'; }
    else if (ИСКЛЮЧЕНИЯ[з.имя]) { папка = ИСКЛЮЧЕНИЯ[з.имя]; почему = 'исключение'; }
    else if (В_ОБЩЕЕ_CASUAL.test(з.имя)) { папка = 'общее/casual'; почему = 'общий набор простых игр'; }
    else if (страницыФайла.length >= 2) { папка = з.вид === 'css' ? 'общее/css' : 'общее/js'; почему = 'страниц: ' + страницыФайла.length; }
    else if (страницыФайла.length === 1) {
      const страница = страницыФайла[0];
      папка = 'игры/' + (ИГРА_СТРАНИЦЫ[страница] || страница.replace(/\.html$/, ''));
      почему = 'одна страница: ' + страница;
      if (страница === 'index.html') итог.индексныеВДурака.push(з.имя);
    } else {
      // Ни одна страница не подключает: кладём по приставке имени, иначе — в общее.
      const игра = играПоИмени(з.имя, игры);
      папка = игра ? 'игры/' + игра : (з.вид === 'css' ? 'общее/css' : 'общее/js');
      // «Сирота» — файл, который не просит никто: ни страница, ни сервер, ни бот, ни проверка, ни другой файл.
      const нужныеГруппы = группы.filter((г) => г !== 'документы');
      if (нужныеГруппы.length === 0) { почему = 'сирота, ' + (игра ? 'по приставке имени' : 'приставка не совпала ни с одной игрой'); итог.сироты.push(з.имя); }
      else { почему = 'страницы не подключают, просят: ' + нужныеГруппы.join(', ') + (игра ? '; по приставке имени' : '; приставка не совпала'); итог.безСтраницНоНужны.push(з.имя); }
    }
    з.новаяПапка = папка;
    з.новый = папка + '/' + з.имя;
    з.почему = почему;
  }
  return итог;
}

