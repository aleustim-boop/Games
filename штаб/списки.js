/*
  Переписывает в ЗАДАЧИ.md разделы «Очередь», «Ждём слова владельца»
  и дописывает в «Готово» то, что программа сама опознала как сделанное.

  Зачем. Владелец спросил: «почему в дашборде у меня постоянно висит
  9 задач в очереди?» Пять из девяти были давно сделаны и опубликованы —
  просто их некому было вычеркнуть, кроме памяти штаба. Раздел «В работе»
  к тому времени уже вела программа (штаб/в-работе.js), а очередь осталась
  на памяти. Теперь и она на программе.

  Зовётся одной короткой строкой:

      node штаб/списки.js

  Данные лежат в штаб/списки.json: список «очередь» и список «вопросы».
  Как задаётся примета «дело сделано» — подробно расписано в штаб/сделано.js.

  Чего эта программа НЕ трогает: разделы, которые штаб пишет руками
  («ЧИТАТЬ ПЕРВЫМ ДЕЛОМ ПОСЛЕ ПЕРЕЗАПУСКА», пояснения вверху, «Долги
  команды», «Новое от владельца»). Она правит ровно три своих раздела.
*/

'use strict';

const fs = require('fs');
const path = require('path');
const сделано = require('./сделано.js');

const КОРЕНЬ = path.join(__dirname, '..');
const ФАЙЛ_ЗАДАЧ = path.join(КОРЕНЬ, 'ЗАДАЧИ.md');
const ФАЙЛ_СПИСКОВ = path.join(__dirname, 'списки.json');

const ЗАГОЛОВОК_ОЧЕРЕДИ = '## Очередь: что увидит игрок';
const ЗАГОЛОВОК_ВОПРОСОВ = '## Ждём слова владельца';
const ЗАГОЛОВОК_ГОТОВО = '## Готово и уже у игроков';
const ЗАГОЛОВОК_ДОЛГОВ = '## Долги команды';

const МЕСЯЦЫ = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
  'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];

/** «8 сентября, 14:22» — так же, как уже написано в таблице «Готово». */
function когдаСловами(дата) {
  const дв = function (ч) { return String(ч).padStart(2, '0'); };
  return дата.getDate() + ' ' + МЕСЯЦЫ[дата.getMonth()] + ', ' + дв(дата.getHours()) + ':' + дв(дата.getMinutes());
}

/** Голый текст пункта: без звёздочек, чтобы в таблице «Готово» было ровно. */
function безРазметки(текст) {
  return String(текст).replace(/\*\*/g, '').trim();
}

/* ---------------------------------------------------------------------------
   Работа с текстом ЗАДАЧИ.md — только свои разделы
--------------------------------------------------------------------------- */

/** Где начинается и где кончается раздел. Нет такого — вернём null. */
function границыРаздела(текст, заголовок) {
  const начало = текст.indexOf(заголовок);
  if (начало < 0) return null;
  const дальше = текст.indexOf('\n## ', начало + 5);
  return { начало: начало, конец: дальше < 0 ? текст.length : дальше + 1 };
}

/** Заменяем свой раздел целиком. Нет раздела — вставляем перед указанным. */
function поставитьРаздел(текст, заголовок, новый, передЗаголовком) {
  const место = границыРаздела(текст, заголовок);
  if (место) return текст.slice(0, место.начало) + новый + текст.slice(место.конец);

  const куда = передЗаголовком ? текст.indexOf(передЗаголовком) : -1;
  if (куда >= 0) return текст.slice(0, куда) + новый + текст.slice(куда);
  return текст + '\n' + новый;
}

/**
 * Дописываем строки в таблицу «Готово», не переписывая её целиком:
 * там лежит история, которую вела рука, и терять её нельзя.
 * Новые строки встают сразу под шапкой таблицы — сверху, как самые свежие.
 */
function дописатьВГотово(текст, строки) {
  if (!строки.length) return { текст: текст, добавлено: 0 };

  const место = границыРаздела(текст, ЗАГОЛОВОК_ГОТОВО);
  if (!место) {
    console.log('в ЗАДАЧИ.md нет раздела «Готово и уже у игроков» — сделанное дописывать некуда');
    return { текст: текст, добавлено: 0 };
  }

  let раздел = текст.slice(место.начало, место.конец);
  const разделитель = /\n\|\s*-{2,}[^\n]*\n/.exec(раздел);
  if (!разделитель) {
    console.log('в разделе «Готово» не нашлась таблица — дописывать некуда');
    return { текст: текст, добавлено: 0 };
  }

  // Задвоения быть не должно: программу зовут по многу раз в день.
  const новые = строки.filter(function (с) { return раздел.indexOf(с.ключ) === -1; });
  if (!новые.length) return { текст: текст, добавлено: 0 };

  const место_вставки = разделитель.index + разделитель[0].length;
  раздел = раздел.slice(0, место_вставки)
    + новые.map(function (с) { return с.строка; }).join('\n') + '\n'
    + раздел.slice(место_вставки);

  return {
    текст: текст.slice(0, место.начало) + раздел + текст.slice(место.конец),
    добавлено: новые.length
  };
}

/* ---------------------------------------------------------------------------
   Сборка разделов
--------------------------------------------------------------------------- */

function разделОчереди(пункты, подсказки) {
  let раздел = ЗАГОЛОВОК_ОЧЕРЕДИ + '\n\n'
    + 'Сверху — то, что берём первым. Только то, что меняет игру для человека.\n'
    + 'Раздел переписывает `node штаб/списки.js` по файлу `штаб/списки.json`:\n'
    + 'сделанное вычёркивается само, по следу в коде и в записях git.\n\n';

  if (!пункты.length) {
    раздел += '**Очередь пуста.** Всё, что было в списке, программа опознала как сделанное.\n'
      + 'Если владелец ждёт чего-то ещё — этого просто нет в `штаб/списки.json`.\n\n';
    return раздел;
  }

  раздел += '| Что | Важность | Заметка штаба |\n|---|---|---|\n';
  for (const п of пункты) {
    const важность = (п.важность === 'потом' || п.важность === 'задел')
      ? п.важность
      : '**' + п.важность + '**';
    let заметка = п.заметка || '';
    const подсказка = подсказки.get(п.что);
    if (подсказка) {
      заметка += (заметка ? ' ' : '')
        + '⚠️ в записях git есть похожее: «' + подсказка.что + '» — проверьте, не сделано ли';
    }
    раздел += '| ' + п.что + ' | ' + важность + ' | ' + заметка + ' |\n';
  }
  return раздел + '\n';
}

function разделВопросов(вопросы) {
  let раздел = ЗАГОЛОВОК_ВОПРОСОВ + '\n\n'
    + 'Это не долг команды и не очередь: тут работы на несколько строк, но решать\n'
    + 'должен владелец — это его игра. Пока ответа нет, пункты стоят, и стоят они\n'
    + 'не по нашей лени. Раздел ведёт `node штаб/списки.js`.\n\n';

  if (!вопросы.length) {
    раздел += '**Открытых вопросов нет** — всё, что нужно было решить, владелец решил.\n\n';
    return раздел;
  }

  раздел += '| О чём | Вопрос владельцу | Почему спрашиваем |\n|---|---|---|\n';
  for (const в of вопросы) {
    раздел += '| ' + (в.что || '') + ' | **' + (в.вопрос || '') + '** | ' + (в.заметка || '') + ' |\n';
  }
  return раздел + '\n';
}

/* ---------------------------------------------------------------------------
   Главное
--------------------------------------------------------------------------- */

if (!fs.existsSync(ФАЙЛ_СПИСКОВ)) {
  console.log('нет файла ' + ФАЙЛ_СПИСКОВ + ' — напишите его и позовите снова');
  process.exit(1);
}

const данные = JSON.parse(fs.readFileSync(ФАЙЛ_СПИСКОВ, 'utf8'));
const очередь = Array.isArray(данные.очередь) ? данные.очередь : [];
const вопросы = Array.isArray(данные.вопросы) ? данные.вопросы : [];

const записи = сделано.записиGit(300);
if (записи === null) {
  console.log('git не ответил — сверять сделанное не с чем, разделы не тронуты');
  process.exit(1);
}

const остались = [];
const уехали = [];
const подсказки = new Map();

for (const пункт of очередь) {
  const разбор = сделано.разобратьПункт(пункт, записи);
  if (разбор.сделан) {
    уехали.push({ пункт: пункт, чем: разбор.чем, когда: разбор.когда });
    continue;
  }
  остались.push(пункт);
  if (разбор.подсказка) подсказки.set(пункт.что, разбор.подсказка);
}

// Строки для таблицы «Готово». Время — только настоящее, из git.
// Не нашлось — так и пишем, а не подставляем «сейчас».
const строкиГотово = уехали.map(function (у) {
  const текст = безРазметки(у.пункт.что);
  const когда = у.когда ? когдаСловами(у.когда) : 'время из git не нашлось';
  return { ключ: текст, строка: '| ' + текст + ' | ' + когда + ' |' };
});

let текст = fs.readFileSync(ФАЙЛ_ЗАДАЧ, 'utf8');
текст = поставитьРаздел(текст, ЗАГОЛОВОК_ОЧЕРЕДИ, разделОчереди(остались, подсказки), ЗАГОЛОВОК_ДОЛГОВ);
текст = поставитьРаздел(текст, ЗАГОЛОВОК_ВОПРОСОВ, разделВопросов(вопросы), ЗАГОЛОВОК_ДОЛГОВ);
const сГотовым = дописатьВГотово(текст, строкиГотово);
fs.writeFileSync(ФАЙЛ_ЗАДАЧ, сГотовым.текст, 'utf8');

// Уехавшие убираем из списка, чтобы при следующем запуске их не разбирать
// заново и не задваивать строку в «Готово».
if (уехали.length) {
  данные.очередь = остались;
  fs.writeFileSync(ФАЙЛ_СПИСКОВ, JSON.stringify(данные, null, 2) + '\n', 'utf8');
}

console.log('в очереди осталось: ' + остались.length + ', вопросов владельцу: ' + вопросы.length);
if (уехали.length) {
  console.log('опознано сделанным (' + уехали.length + '):');
  for (const у of уехали) {
    console.log('  · ' + безРазметки(у.пункт.что));
    console.log('      признак: ' + у.чем + '; время: ' + (у.когда ? когдаСловами(у.когда) : 'из git не нашлось'));
  }
  console.log('дописано строк в «Готово»: ' + сГотовым.добавлено);
}
if (подсказки.size) {
  console.log('похоже на сделанное, но примета не сработала — проверьте руками (' + подсказки.size + '):');
  for (const [что, п] of подсказки) console.log('  · ' + безРазметки(что) + ' ← «' + п.что + '»');
}
