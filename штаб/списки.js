/*
  Переписывает в ЗАДАЧИ.md разделы «Очередь», «Ждём слова владельца»
  и дописывает в «Готово» то, что программа сама опознала как сделанное.

  Зачем. Владелец спросил: «почему в дашборде у меня постоянно висит
  9 задач в очереди?» Пять из девяти были давно сделаны и опубликованы —
  просто их некому было вычеркнуть, кроме памяти штаба. Раздел «В работе»
  к тому времени уже вела программа (штаб/в-работе.js), а очередь осталась
  на памяти. Теперь и она на программе.

  Зовётся одной короткой строкой:

      node штаб/списки.js

  Данные лежат в штаб/списки.json, в поле «очередь». Вопросы к владельцу
  здесь больше не живут: они переехали в штаб/важное.json, и раздел
  «Ждём слова владельца» пишет node штаб/важное.js.
  Как задаётся примета «дело сделано» — подробно расписано в штаб/сделано.js.

  Чего эта программа НЕ трогает: разделы, которые штаб пишет руками
  («ЧИТАТЬ ПЕРВЫМ ДЕЛОМ ПОСЛЕ ПЕРЕЗАПУСКА», пояснения вверху). Она правит
  ровно три своих раздела.

  С 16 сентября (волна хвостов) очередь в ЗАДАЧИ.md показывает только
  «горит» и «скоро» — остальное («потом», «задел») программа пишет отдельным
  файлом штаб/очередь.md, чтобы ЗАДАЧИ.md не разрасталось.

  С 16 сентября (волна хвостов, финал) «Готово» тоже не копится вечно:
  при каждом запуске программа сама переносит строки старше СРОК_АРХИВА_ГОТОВО
  дней в штаб/архив-задач.md — дословно, той же строкой таблицы. Строку,
  чьё время не разобрать («время из git не нашлось» и подобное), не трогаем —
  честное «не знаю» не даёт повода выдумывать возраст записи.
*/

'use strict';

const fs = require('fs');
const path = require('path');
const сделано = require('./сделано.js');

const КОРЕНЬ = path.join(__dirname, '..');
const ФАЙЛ_ЗАДАЧ = path.join(КОРЕНЬ, 'ЗАДАЧИ.md');
const ФАЙЛ_СПИСКОВ = path.join(__dirname, 'списки.json');
const ФАЙЛ_ОЧЕРЕДЬ_ОСТАЛЬНОЕ = path.join(__dirname, 'очередь.md');
const ФАЙЛ_АРХИВА = path.join(__dirname, 'архив-задач.md');

const ЗАГОЛОВОК_ОЧЕРЕДИ = '## Очередь: что увидит игрок';
const ЗАГОЛОВОК_ВОПРОСОВ = '## Ждём слова владельца';
const ЗАГОЛОВОК_ГОТОВО = '## Готово и уже у игроков';
const СРОК_АРХИВА_ГОТОВО = 7; // дней — строки таблицы «Готово» старше этого уезжают в архив

const МЕСЯЦЫ = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
  'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];

/** «8 сентября, 14:22» — так же, как уже написано в таблице «Готово». */
function когдаСловами(дата) {
  const дв = function (ч) { return String(ч).padStart(2, '0'); };
  return дата.getDate() + ' ' + МЕСЯЦЫ[дата.getMonth()] + ', ' + дв(дата.getHours()) + ':' + дв(дата.getMinutes());
}

/** Голый текст пункта: без звёздочек, чтобы в таблице «Готово» было ровно. */
function безРазметки(текст) {
  return String(текст).replace(/\*\*/g, '').trim();
}

/**
 * Обратное к когдаСловами(): «16 сентября, 14:53» → Date. Год в таблице
 * не пишется, берём текущий; если получилась дата в будущем — это была
 * прошлогодняя запись. Не разобрали (например «время из git не нашлось») —
 * честный null, а не выдумка.
 */
function разобратьКогда(текст, сейчас) {
  const строка = String(текст || '').trim();
  const совпадение = /^(\d{1,2})\s+([а-яё]+)(?:,\s*(\d{1,2}):(\d{2}))?/i.exec(строка);
  if (!совпадение) return null;
  const месяц = МЕСЯЦЫ.indexOf(совпадение[2].toLowerCase());
  if (месяц < 0) return null;
  const момент = сейчас || Date.now();
  const база = new Date(момент);
  const дата = new Date(база.getFullYear(), месяц, Number(совпадение[1]),
    совпадение[3] ? Number(совпадение[3]) : 0, совпадение[4] ? Number(совпадение[4]) : 0);
  if (isNaN(дата.getTime())) return null;
  if (дата.getTime() > момент + 60000) дата.setFullYear(дата.getFullYear() - 1);
  return дата;
}

/* ---------------------------------------------------------------------------
   Работа с текстом ЗАДАЧИ.md — только свои разделы
--------------------------------------------------------------------------- */

/** Где начинается и где кончается раздел. Нет такого — вернём null. */
function границыРаздела(текст, заголовок) {
  const начало = текст.indexOf(заголовок);
  if (начало < 0) return null;
  const дальше = текст.indexOf('\n## ', начало + 5);
  return { начало: начало, конец: дальше < 0 ? текст.length : дальше + 1 };
}

/** Заменяем свой раздел целиком. Нет раздела — вставляем перед указанным. */
function поставитьРаздел(текст, заголовок, новый, передЗаголовком) {
  const место = границыРаздела(текст, заголовок);
  if (место) return текст.slice(0, место.начало) + новый + текст.slice(место.конец);

  const куда = передЗаголовком ? текст.indexOf(передЗаголовком) : -1;
  if (куда >= 0) return текст.slice(0, куда) + новый + текст.slice(куда);
  return текст + '\n' + новый;
}

/**
 * Дописываем строки в таблицу «Готово», не переписывая её целиком:
 * там лежит история, которую вела рука, и терять её нельзя.
 * Новые строки встают сразу под шапкой таблицы — сверху, как самые свежие.
 */
function дописатьВГотово(текст, строки) {
  if (!строки.length) return { текст: текст, добавлено: 0 };

  const место = границыРаздела(текст, ЗАГОЛОВОК_ГОТОВО);
  if (!место) {
    console.log('в ЗАДАЧИ.md нет раздела «Готово и уже у игроков» — сделанное дописывать некуда');
    return { текст: текст, добавлено: 0 };
  }

  let раздел = текст.slice(место.начало, место.конец);
  const разделитель = /\n\|\s*-{2,}[^\n]*\n/.exec(раздел);
  if (!разделитель) {
    console.log('в разделе «Готово» не нашлась таблица — дописывать некуда');
    return { текст: текст, добавлено: 0 };
  }

  // Задвоения быть не должно: программу зовут по многу раз в день.
  const новые = строки.filter(function (с) { return раздел.indexOf(с.ключ) === -1; });
  if (!новые.length) return { текст: текст, добавлено: 0 };

  const место_вставки = разделитель.index + разделитель[0].length;
  раздел = раздел.slice(0, место_вставки)
    + новые.map(function (с) { return с.строка; }).join('\n') + '\n'
    + раздел.slice(место_вставки);

  return {
    текст: текст.slice(0, место.начало) + раздел + текст.slice(место.конец),
    добавлено: новые.length
  };
}

/** Строки таблицы «Готово» между разделителем и концом раздела, и что вокруг них. */
function разобратьТаблицуГотово(раздел) {
  const строкиРаздела = раздел.split('\n');
  const индексРазделителя = строкиРаздела.findIndex(function (с) { return /^\|\s*-{2,}/.test(с.trim()); });
  if (индексРазделителя < 0) return null;

  let конецТаблицы = индексРазделителя + 1;
  while (конецТаблицы < строкиРаздела.length && строкиРаздела[конецТаблицы].trim().startsWith('|')) конецТаблицы += 1;

  return {
    до: строкиРаздела.slice(0, индексРазделителя + 1),
    строки: строкиРаздела.slice(индексРазделителя + 1, конецТаблицы),
    после: строкиРаздела.slice(конецТаблицы)
  };
}

/**
 * Уносит из таблицы «Готово» строки старше СРОК_АРХИВА_ГОТОВО дней —
 * дословно, в штаб/архив-задач.md. Строку, чьё «Когда» не разобралось,
 * не трогаем: не знаем возраста — не архивируем.
 */
function архивироватьСтарыеСтроки(текст, сейчас) {
  const место = границыРаздела(текст, ЗАГОЛОВОК_ГОТОВО);
  if (!место) return { текст: текст, ушли: [] };

  const раздел = текст.slice(место.начало, место.конец);
  const таблица = разобратьТаблицуГотово(раздел);
  if (!таблица) return { текст: текст, ушли: [] };

  const рубеж = (сейчас || Date.now()) - СРОК_АРХИВА_ГОТОВО * 24 * 60 * 60 * 1000;
  const оставить = [];
  const ушли = [];

  for (const строка of таблица.строки) {
    const колонки = строка.split('|').slice(1, -1).map(function (ч) { return ч.trim(); });
    const дата = колонки.length >= 2 ? разобратьКогда(колонки[1], сейчас) : null;
    if (дата && дата.getTime() < рубеж) ушли.push(строка);
    else оставить.push(строка);
  }

  if (!ушли.length) return { текст: текст, ушли: [] };

  const строкиНовые = таблица.до
    .concat(оставить.length ? оставить : ['*(новых строк нет — последние уехали в архив)*'])
    .concat(таблица.после);
  const разделНовый = строкиНовые.join('\n');

  return {
    текст: текст.slice(0, место.начало) + разделНовый + текст.slice(место.конец),
    ушли: ушли
  };
}

/** Дописывает уехавшие из «Готово» строки в штаб/архив-задач.md, под его таблицу. */
function дописатьВАрхив(строки) {
  if (!строки.length) return;
  let архив = fs.readFileSync(ФАЙЛ_АРХИВА, 'utf8');
  const разделитель = /\n\|\s*-{2,}[^\n]*\n/.exec(архив);
  if (!разделитель) {
    console.log('в штаб/архив-задач.md не нашлась таблица — строки «Готово» не унесены, останутся в ЗАДАЧИ.md');
    return false;
  }
  const место = разделитель.index + разделитель[0].length;
  архив = архив.slice(0, место) + строки.join('\n') + '\n' + архив.slice(место);
  fs.writeFileSync(ФАЙЛ_АРХИВА, архив, 'utf8');
  return true;
}

/* ---------------------------------------------------------------------------
   Сборка разделов
--------------------------------------------------------------------------- */

function строкаОчереди(п, подсказки) {
  const важность = (п.важность === 'потом' || п.важность === 'задел')
    ? п.важность
    : '**' + п.важность + '**';
  let заметка = п.заметка || '';
  const подсказка = подсказки.get(п.что);
  if (подсказка) {
    заметка += (заметка ? ' ' : '')
      + '⚠️ в записях git есть похожее: «' + подсказка.что + '» — проверьте, не сделано ли';
  }
  return '| ' + п.что + ' | ' + важность + ' | ' + заметка + ' |\n';
}

/** В ЗАДАЧИ.md — только горящее и ожидаемое; остальное — в штаб/очередь.md. */
function разделОчереди(пункты, подсказки) {
  let раздел = ЗАГОЛОВОК_ОЧЕРЕДИ + '\n\n'
    + 'Сверху — то, что берём первым: важность «горит» или «скоро». Только то,\n'
    + 'что меняет игру для человека прямо сейчас. Остальное («потом», «задел») —\n'
    + 'файл `штаб/очередь.md`, его пишет та же программа.\n'
    + 'Раздел переписывает `node штаб/списки.js` по файлу `штаб/списки.json`:\n'
    + 'сделанное вычёркивается само, по следу в коде и в записях git.\n\n';

  const горящие = пункты.filter(function (п) { return п.важность === 'горит' || п.важность === 'скоро'; });

  if (!горящие.length) {
    раздел += '**Срочного и ожидаемого в очереди нет.** Остальное («потом», «задел») —\n'
      + 'в `штаб/очередь.md`.\n\n';
    return раздел;
  }

  раздел += '| Что | Важность | Заметка штаба |\n|---|---|---|\n';
  for (const п of горящие) раздел += строкаОчереди(п, подсказки);
  return раздел + '\n';
}

/** Отдельный файл: «потом» и «задел» — чтобы не раздувать ЗАДАЧИ.md. */
function файлОчередиОстальное(пункты, подсказки) {
  const остальные = пункты.filter(function (п) { return п.важность === 'потом' || п.важность === 'задел'; });

  let текст = '# Очередь: потом и задел\n\n'
    + 'Не срочное. «Потом» — нужное, но никто не ждёт; «задел» — не начинать,\n'
    + 'пока не спросят. Горящее и ожидаемое — в `ЗАДАЧИ.md`, раздел «Очередь: что\n'
    + 'увидит игрок». Файл переписывает `node штаб/списки.js` по `штаб/списки.json`;\n'
    + 'сделанное вычёркивается само, по следу в коде и в записях git.\n\n';

  if (!остальные.length) {
    текст += '**Пусто.**\n';
    return текст;
  }

  текст += '| Что | Важность | Заметка штаба |\n|---|---|---|\n';
  for (const п of остальные) текст += строкаОчереди(п, подсказки);
  return текст;
}

function разделВопросов(вопросы) {
  let раздел = ЗАГОЛОВОК_ВОПРОСОВ + '\n\n'
    + 'Это не долг команды и не очередь: тут работы на несколько строк, но решать\n'
    + 'должен владелец — это его игра. Пока ответа нет, пункты стоят, и стоят они\n'
    + 'не по нашей лени. Раздел ведёт `node штаб/списки.js`.\n\n';

  if (!вопросы.length) {
    раздел += '**Открытых вопросов нет** — всё, что нужно было решить, владелец решил.\n\n';
    return раздел;
  }

  раздел += '| О чём | Вопрос владельцу | Почему спрашиваем |\n|---|---|---|\n';
  for (const в of вопросы) {
    раздел += '| ' + (в.что || '') + ' | **' + (в.вопрос || '') + '** | ' + (в.заметка || '') + ' |\n';
  }
  return раздел + '\n';
}

/* ---------------------------------------------------------------------------
   Главное
--------------------------------------------------------------------------- */

if (!fs.existsSync(ФАЙЛ_СПИСКОВ)) {
  console.log('нет файла ' + ФАЙЛ_СПИСКОВ + ' — напишите его и позовите снова');
  process.exit(1);
}

const данные = JSON.parse(fs.readFileSync(ФАЙЛ_СПИСКОВ, 'utf8'));
const очередь = Array.isArray(данные.очередь) ? данные.очередь : [];
/* Вопросы владельцу переехали в штаб/важное.json, и раздел «Ждём слова
   владельца» теперь пишет только штаб/важное.js. Если поля «вопросы» в
   файле нет — эта программа тот раздел не трогает вовсе: два хозяина у
   одного раздела означали бы, что они затирают работу друг друга. */
const вопросы = Array.isArray(данные.вопросы) ? данные.вопросы : null;

const записи = сделано.записиGit(300);
if (записи === null) {
  console.log('git не ответил — сверять сделанное не с чем, разделы не тронуты');
  process.exit(1);
}

const остались = [];
const уехали = [];
const подсказки = new Map();

for (const пункт of очередь) {
  const разбор = сделано.разобратьПункт(пункт, записи);
  if (разбор.сделан) {
    уехали.push({ пункт: пункт, чем: разбор.чем, когда: разбор.когда });
    continue;
  }
  остались.push(пункт);
  if (разбор.подсказка) подсказки.set(пункт.что, разбор.подсказка);
}

// Строки для таблицы «Готово». Время — только настоящее, из git.
// Не нашлось — так и пишем, а не подставляем «сейчас».
const строкиГотово = уехали.map(function (у) {
  const текст = безРазметки(у.пункт.что);
  const когда = у.когда ? когдаСловами(у.когда) : 'время из git не нашлось';
  return { ключ: текст, строка: '| ' + текст + ' | ' + когда + ' |' };
});

let текст = fs.readFileSync(ФАЙЛ_ЗАДАЧ, 'utf8');
текст = поставитьРаздел(текст, ЗАГОЛОВОК_ОЧЕРЕДИ, разделОчереди(остались, подсказки), ЗАГОЛОВОК_ГОТОВО);
if (вопросы) {
  текст = поставитьРаздел(текст, ЗАГОЛОВОК_ВОПРОСОВ, разделВопросов(вопросы), ЗАГОЛОВОК_ГОТОВО);
}
const сГотовым = дописатьВГотово(текст, строкиГотово);
const сАрхивом = архивироватьСтарыеСтроки(сГотовым.текст);
if (сАрхивом.ушли.length) дописатьВАрхив(сАрхивом.ушли);
fs.writeFileSync(ФАЙЛ_ЗАДАЧ, сАрхивом.текст, 'utf8');
fs.writeFileSync(ФАЙЛ_ОЧЕРЕДЬ_ОСТАЛЬНОЕ, файлОчередиОстальное(остались, подсказки), 'utf8');

// Уехавшие убираем из списка, чтобы при следующем запуске их не разбирать
// заново и не задваивать строку в «Готово».
if (уехали.length) {
  данные.очередь = остались;
  fs.writeFileSync(ФАЙЛ_СПИСКОВ, JSON.stringify(данные, null, 2) + '\n', 'utf8');
}

console.log('в очереди осталось: ' + остались.length + (вопросы ? ', вопросов владельцу: ' + вопросы.length : ', вопросы ведёт штаб/важное.js'));
if (уехали.length) {
  console.log('опознано сделанным (' + уехали.length + '):');
  for (const у of уехали) {
    console.log('  · ' + безРазметки(у.пункт.что));
    console.log('      признак: ' + у.чем + '; время: ' + (у.когда ? когдаСловами(у.когда) : 'из git не нашлось'));
  }
  console.log('дописано строк в «Готово»: ' + сГотовым.добавлено);
}
if (сАрхивом.ушли.length) {
  console.log('унесено в штаб/архив-задач.md как старше ' + СРОК_АРХИВА_ГОТОВО + ' дней: ' + сАрхивом.ушли.length);
}
