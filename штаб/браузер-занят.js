/*
  Занят ли сейчас браузер чужой проверкой.

  Зачем отдельная программа. Правило проекта — не толпиться в браузере
  (машина уже падала от нескольких проверок сразу). Владелец разрешил
  запускать НЕСКОЛЬКО браузеров разом (24.09) — значит очередь нужна не
  «один и только один», а предел по числу и по свободной памяти.

  Раньше занятым считался любой node.exe с «tests/» в командной строке —
  из-за этого сюда попадали и сетевые проверки без браузера вовсе,
  исполнители стояли в очереди по 40 минут впустую. Теперь считаем ТОЛЬКО
  настоящие браузеры проверок: chrome.exe или chromium.exe, у которых в
  командной строке есть --headless или ms-playwright. Обычный Chrome
  владельца (без этих признаков) не в счёт. У каждого браузера — куча
  дочерних процессов (--type=renderer, --type=gpu-process и т.д.), их не
  считаем: главный процесс — тот, у которого в командной строке НЕТ
  --type=.

      node штаб/браузер-занят.js            — разовая проверка
      node штаб/браузер-занят.js --ждать    — ждать, пока не освободится

  Свободно — печатает одну строку с итогом «свободно», код выхода 0.
  Занято   — печатает одну строку с итогом «занято» и причиной, код 1.
  --ждать  — опрашивает раз в 30 секунд, печатает «жду: …», но не дольше
             20 минут; не дождался — печатает «не дождался», код выхода 2.

  Опрос процессов и памяти может сам по себе не удаться (PowerShell упал,
  ответ пустой и т.п.) — тогда программа не молчит «свободно», а честно
  считает это занятостью и печатает причину.
*/

const os = require('os');
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

/* Постоянные пороги — здесь и только здесь, чтобы не искать по всему файлу. */
const ПРЕДЕЛ_БРАУЗЕРОВ = 3; // разрешаем одновременно не больше стольких браузеров проверок
const ПОРОГ_ПАМЯТИ_МБ = 3072; // меньше — машина уже тесная, считаем занятой (3 ГБ)

/* Признаки настоящего браузера проверки. Имя процесса — chrome.exe или
   chromium.exe; в командной строке обязателен --headless или путь через
   ms-playwright (так Playwright запускает свой скачанный браузер). */
const ИМЯ_БРАУЗЕРА = /^(chrome|chromium)\.exe$/i;
const ПРИЗНАК_ПРОВЕРКИ = /--headless|ms-playwright/i;
/* Дочерний процесс браузера (рендерер, gpu-процесс и т.п.) — у него в
   командной строке всегда есть --type=, у главного процесса — никогда. */
const ПРИЗНАК_ДОЧЕРНЕГО = /--type=/i;

/* Список всех chrome.exe/chromium.exe с их командными строками и объём
   свободной физической памяти — одним вызовом PowerShell. Get-CimInstance
   используем вместо wmic (его на машине нет). Результат гоним через
   временный файл в кодировке utf8 — если читать напрямую из stdout
   PowerShell, кириллица в путях превращается в знаки вопроса из-за
   консольной кодовой страницы, а Out-File -Encoding utf8 этой беды не знает. */
function опроситьСостояние() {
  const файл = path.join(os.tmpdir(), `браузер-занят-${process.pid}.json`);
  const команда =
    "$процессы = Get-CimInstance Win32_Process -Filter \"Name='chrome.exe' OR Name='chromium.exe'\" " +
    '| Select-Object Name,ProcessId,CommandLine; ' +
    '$память = (Get-CimInstance Win32_OperatingSystem).FreePhysicalMemory; ' +
    '[PSCustomObject]@{ Процессы = $процессы; СвободнаяПамятьКБ = $память } ' +
    `| ConvertTo-Json -Depth 4 | Out-File -FilePath '${файл}' -Encoding utf8`;
  try {
    execFileSync('powershell', ['-NoProfile', '-NonInteractive', '-Command', команда], {
      stdio: ['ignore', 'ignore', 'pipe'],
    });
    const текст = fs.readFileSync(файл, 'utf8').replace(/^﻿/, '').trim();
    if (!текст) throw new Error('PowerShell вернул пустой ответ');
    const разобранное = JSON.parse(текст);
    let процессы = разобранное.Процессы;
    if (процессы == null) процессы = [];
    if (!Array.isArray(процессы)) процессы = [процессы]; /* один процесс — Get-CimInstance даёт объект, не массив */
    const свободнойПамятиКБ = Number(разобранное.СвободнаяПамятьКБ);
    const свободнойПамятиМБ = Number.isFinite(свободнойПамятиКБ) ? Math.round(свободнойПамятиКБ / 1024) : null;
    return { процессы, свободнойПамятиМБ };
  } finally {
    try { fs.unlinkSync(файл); } catch (е) { /* временного файла и не было — не беда */ }
  }
}

/* Из сырого списка процессов (Name, ProcessId, CommandLine) оставить только
   главные процессы браузеров проверок — без дочерних. Чистая функция от
   входных данных, PowerShell и файлы сюда не заходят: тест кормит её
   поддельными списками напрямую. */
function отфильтроватьГлавныеБраузеры(процессы) {
  const результат = [];
  for (const п of процессы || []) {
    if (!п || п.CommandLine == null || п.Name == null) continue;
    if (!ИМЯ_БРАУЗЕРА.test(String(п.Name))) continue;
    const команднаяСтрока = String(п.CommandLine);
    if (!ПРИЗНАК_ПРОВЕРКИ.test(команднаяСтрока)) continue;
    if (ПРИЗНАК_ДОЧЕРНЕГО.test(команднаяСтрока)) continue;
    результат.push({ pid: п.ProcessId, доводы: команднаяСтрока });
  }
  return результат;
}

/* Само решение «занято или нет» — тоже чистая функция: на входе уже
   отфильтрованный список главных браузеров проверок и объём свободной
   памяти в МБ (или null, если память узнать не вышло), на выходе — итог. */
function решить(главныеБраузеры, свободнойПамятиМБ) {
  const число = (главныеБраузеры || []).length;

  if (свободнойПамятиМБ != null && свободнойПамятиМБ < ПОРОГ_ПАМЯТИ_МБ) {
    return {
      занято: true,
      число,
      свободнойПамятиМБ,
      причина: `мало свободной памяти: ${свободнойПамятиМБ} МБ < ${ПОРОГ_ПАМЯТИ_МБ} МБ`,
    };
  }

  if (число >= ПРЕДЕЛ_БРАУЗЕРОВ) {
    return {
      занято: true,
      число,
      свободнойПамятиМБ,
      причина: `браузеров проверок уже ${число} (предел ${ПРЕДЕЛ_БРАУЗЕРОВ})`,
    };
  }

  return { занято: false, число, свободнойПамятиМБ, причина: null };
}

/* Полный итог для настоящей машины: опрашивает процессы и память, а если
   опрос упал — честно считает занятость, а не молчит «свободно». */
function получитьИтог() {
  let состояние;
  try {
    состояние = опроситьСостояние();
  } catch (ошибка) {
    return {
      занято: true,
      число: null,
      свободнойПамятиМБ: null,
      причина: 'опрос процессов не удался: ' + (ошибка && ошибка.message ? ошибка.message : String(ошибка)),
    };
  }
  const главные = отфильтроватьГлавныеБраузеры(состояние.процессы);
  return решить(главные, состояние.свободнойПамятиМБ);
}

/* Одна строка на весь итог: сколько браузеров, сколько памяти, вывод. */
function форматСтроки(итог) {
  const числоБраузеров = итог.число == null ? 'неизвестно' : String(итог.число);
  const память = итог.свободнойПамятиМБ == null ? 'неизвестно' : итог.свободнойПамятиМБ + ' МБ';
  const результат = итог.занято ? 'занято' : 'свободно';
  const причина = итог.причина ? ` (${итог.причина})` : '';
  return `браузеров проверок: ${числоБраузеров}, память свободна: ${память} — ${результат}${причина}`;
}

module.exports = {
  ПРЕДЕЛ_БРАУЗЕРОВ,
  ПОРОГ_ПАМЯТИ_МБ,
  ИМЯ_БРАУЗЕРА,
  ПРИЗНАК_ПРОВЕРКИ,
  ПРИЗНАК_ДОЧЕРНЕГО,
  отфильтроватьГлавныеБраузеры,
  решить,
  форматСтроки,
  получитьИтог,
};

/* Запущено напрямую как команда — печатаем и выходим по-старому. */
if (require.main === module) {
  const режимЖдать = process.argv.includes('--ждать');

  if (!режимЖдать) {
    const итог = получитьИтог();
    console.log(форматСтроки(итог));
    process.exit(итог.занято ? 1 : 0);
  } else {
    const ШАГ_МС = 30000;
    const ПРЕДЕЛ_МС = 20 * 60 * 1000;
    const старт = Date.now();

    const шаг = () => {
      const итог = получитьИтог();
      if (!итог.занято) {
        console.log(форматСтроки(итог));
        process.exit(0);
      }
      if (Date.now() - старт >= ПРЕДЕЛ_МС) {
        console.log('не дождался — ' + форматСтроки(итог));
        process.exit(2);
      }
      console.log('жду: ' + форматСтроки(итог));
      setTimeout(шаг, ШАГ_МС);
    };

    шаг();
  }
}
