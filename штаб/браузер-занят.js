/*
  Занят ли сейчас браузер чужой проверкой.

  Зачем отдельная программа. Правило проекта — не больше одной браузерной
  проверки разом (машина уже падала от нескольких одновременно). Раньше это
  смотрели командой `wmic process …`, но на этой машине (Windows 11, сборка
  26200) команды wmic нет вовсе — она молча ничего не находит. Теперь так:

      node штаб/браузер-занят.js            — разовая проверка
      node штаб/браузер-занят.js --ждать    — ждать, пока не освободится

  Свободно — печатает «свободно», код выхода 0.
  Занято   — печатает по строке на каждый чужой процесс (PID, путь до файла
             проверки, вся его командная строка), код выхода 1.
  --ждать  — опрашивает раз в 30 секунд, печатает «жду: …», но не дольше
             20 минут; не дождался — печатает «не дождался», код выхода 2.
*/

const os = require('os');
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

/* Файл «локальный-сервер.js» — стенд страниц на 8080, он живёт постоянно
   и браузер не занимает, его в список чужих проверок включать не надо. */
const ИСКЛЮЧЕНИЕ = /локальный-сервер\.js/i;
/* Признак файла проверки — путь внутри папки tests, косая или обратная. */
const ПРИЗНАК_ПРОВЕРКИ = /tests[\\/]/i;
const ПУТЬ_ИЗ_КОМАНДНОЙ_СТРОКИ = /[^\s"]*tests[\\/][^\s"]+\.js/i;

/* Список всех запущенных node.exe с их командными строками.
   Get-CimInstance используем вместо wmic (его на машине нет). Результат
   гоним через временный файл в кодировке utf8 — если читать напрямую из
   stdout PowerShell, кириллица в путях превращается в знаки вопроса из-за
   консольной кодовой страницы, а Out-File -Encoding utf8 этой беды не знает. */
function получитьПроцессыNode() {
  const файл = path.join(os.tmpdir(), `браузер-занят-${process.pid}.json`);
  const команда =
    "Get-CimInstance Win32_Process -Filter \"name='node.exe'\" " +
    '| Select-Object ProcessId,CommandLine | ConvertTo-Json ' +
    `| Out-File -FilePath '${файл}' -Encoding utf8`;
  try {
    execFileSync('powershell', ['-NoProfile', '-NonInteractive', '-Command', команда], {
      stdio: ['ignore', 'ignore', 'pipe'],
    });
    const текст = fs.readFileSync(файл, 'utf8').replace(/^﻿/, '').trim();
    if (!текст) return [];
    const разобранное = JSON.parse(текст);
    /* Один процесс — Get-CimInstance даёт объект, не массив: приводим сами. */
    return Array.isArray(разобранное) ? разобранное : [разобранное];
  } finally {
    try { fs.unlinkSync(файл); } catch (е) { /* временного файла и не было — не беда */ }
  }
}

/* Чужие процессы браузерных проверок: свой pid и локальный-сервер.js убираем. */
function найтиЗанятость() {
  const процессы = получитьПроцессыNode();
  const результат = [];
  for (const п of процессы) {
    if (!п || п.CommandLine == null) continue;
    const номерПроцесса = п.ProcessId;
    if (номерПроцесса === process.pid) continue; /* это мы сами */
    const команднаяСтрока = String(п.CommandLine);
    if (!ПРИЗНАК_ПРОВЕРКИ.test(команднаяСтрока)) continue;
    if (ИСКЛЮЧЕНИЕ.test(команднаяСтрока)) continue;
    const совпадение = команднаяСтрока.match(ПУТЬ_ИЗ_КОМАНДНОЙ_СТРОКИ);
    результат.push({
      pid: номерПроцесса,
      путь: совпадение ? совпадение[0] : команднаяСтрока,
      доводы: команднаяСтрока,
    });
  }
  return результат;
}

function печатьЗанятости(список) {
  for (const п of список) console.log(`${п.pid}  ${п.путь}  ${п.доводы}`);
}

const режимЖдать = process.argv.includes('--ждать');

if (!режимЖдать) {
  const список = найтиЗанятость();
  if (список.length === 0) {
    console.log('свободно');
    process.exit(0);
  }
  печатьЗанятости(список);
  process.exit(1);
}

/* Режим ожидания: опрашиваем раз в 30 секунд, но не дольше 20 минут. */
const ШАГ_МС = 30000;
const ПРЕДЕЛ_МС = 20 * 60 * 1000;
const старт = Date.now();

function шаг() {
  const список = найтиЗанятость();
  if (список.length === 0) {
    console.log('свободно');
    process.exit(0);
  }
  if (Date.now() - старт >= ПРЕДЕЛ_МС) {
    console.log('не дождался');
    process.exit(2);
  }
  console.log('жду: ' + список.map((п) => `${п.pid} ${п.путь}`).join(', '));
  setTimeout(шаг, ШАГ_МС);
}

шаг();
