// Часовое обновление дашборда БЕЗ модели.
// Один проход собирает состояние (дашборд, адрес игры, машины, ответы, письма,
// вопросы, коммит, кто молчит), сравнивает с прошлым и печатает только разницу.
// Штаб просыпается лишь когда код выхода 1 (что-то изменилось).
//
//   node штаб/обновление-дашборда.js                   один проход
//   node штаб/обновление-дашборда.js --сторожить [мин] цикл; молчит, пока нет изменений
//   node штаб/обновление-дашборда.js --проверить       самопроверка без сети
const fs = require('fs');
const path = require('path');
const http = require('http');
const https = require('https');
const { execFileSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const ФАЙЛ_СОСТОЯНИЯ = path.join(__dirname, 'обновление-состояние.json');
const ФАЙЛ_В_РАБОТЕ = path.join(__dirname, 'в-работе.json');
const АДРЕС_ИГРЫ = 'https://igra.medart.com.ua/index.html';

// ---------- чистые функции (их проверяет --проверить) ----------

function двеЦифры(n) { return String(n).padStart(2, '0'); }

function времяСтрокой(д) {
  return двеЦифры(д.getDate()) + '.' + двеЦифры(д.getMonth() + 1) + ' ' +
    двеЦифры(д.getHours()) + ':' + двеЦифры(д.getMinutes());
}

// Заменяет только ведущее «ДД.ММ ЧЧ:ММ.»; заметка без даты возвращается как есть.
function заменитьВремя(заметка, время) {
  const м = /^\d{2}\.\d{2} \d{2}:\d{2}(?=\.)/.exec(заметка);
  if (!м) return заметка;
  return время + заметка.slice(м[0].length);
}

const ЧЕЛОВЕЧЕСКИЕ_ИМЕНА = {
  кодАдреса: 'адрес игры (код ответа)',
  npОнлайн: 'машина np-ubuntu на связи',
  igra2Онлайн: 'машина igra2 на связи',
  ответов: 'ответов владельца',
  ответПоследний: 'время последнего ответа',
  писем: 'писем владельца',
  письмоПоследнее: 'время последнего письма',
  нуженОтвет: 'вопросов ждут владельца',
  коммит: 'последний коммит',
  молчат: 'исполнители (кто-молчит)',
};

function показать(значение) {
  if (значение === true) return 'да';
  if (значение === false) return 'нет';
  if (значение === null || значение === undefined || значение === '') return 'нет данных';
  return String(значение);
}

// Возвращает список строк «что изменилось: было → стало». Пусто — изменений нет.
// Нет прошлого состояния — считаем, что изменилось всё.
function сравнить(было, стало) {
  const прошлое = было || {};
  const строки = [];
  for (const ключ of Object.keys(ЧЕЛОВЕЧЕСКИЕ_ИМЕНА)) {
    if (JSON.stringify(прошлое[ключ]) !== JSON.stringify(стало[ключ])) {
      строки.push(ЧЕЛОВЕЧЕСКИЕ_ИМЕНА[ключ] + ': ' + показать(прошлое[ключ]) + ' → ' + показать(стало[ключ]));
    }
  }
  return строки;
}

// Горит: игра не открывается или боевая машина не на связи.
function чтоГорит(с) {
  const причины = [];
  if (с.кодАдреса !== 200) причины.push('игра не открывается (ответ ' + (с.кодАдреса || 'нет связи') + ')');
  if (с.npОнлайн === false) причины.push('машина np-ubuntu не на связи');
  return причины;
}

// Итог для печати: { текст, изменилось }
function собратьИтог(было, стало, времяЧЧММ) {
  const изменения = сравнить(было, стало);
  const горит = чтоГорит(стало);
  if (изменения.length === 0) {
    let хвост = '';
    if (горит.length) хвост = ' (' + (стало.кодАдреса !== 200 ? 'игра по-прежнему не открывается' : 'машина np-ubuntu по-прежнему не на связи') + ')';
    return { текст: 'без изменений ' + времяЧЧММ + хвост, изменилось: false };
  }
  const строки = [];
  const перехода = !было || было.кодАдреса !== стало.кодАдреса || было.npОнлайн !== стало.npОнлайн;
  if (горит.length && перехода) строки.push('ГОРИТ: ' + горит.join('; '));
  строки.push('что изменилось:');
  for (const с of изменения) строки.push('- ' + с);
  return { текст: строки.join('\n'), изменилось: true };
}

// ---------- сбор состояния ----------

function запрос(модуль, адрес, срокМс) {
  return new Promise((готово) => {
    let отвечено = false;
    const конец = (код) => { if (!отвечено) { отвечено = true; готово(код); } };
    try {
      const з = модуль.get(адрес, { timeout: срокМс }, (о) => { о.resume(); конец(о.statusCode); });
      з.on('timeout', () => { з.destroy(); конец(0); });
      з.on('error', () => конец(0));
    } catch (_) { конец(0); }
  });
}

function командаУзла(аргументы, срокМс) {
  return execFileSync(process.execPath, аргументы, {
    cwd: КОРЕНЬ, encoding: 'utf8', timeout: срокМс, stdio: ['ignore', 'pipe', 'pipe'],
  });
}

async function проверитьДашборд() {
  const код = await запрос(http, 'http://127.0.0.1:8791/' + encodeURIComponent('жив'), 5000);
  if (код === 200) return { ок: true, заметка: '' };
  try { командаУзла([path.join('штаб', 'перезапуск-дашборда.js')], 30000); } catch (_) { /* итог ниже */ }
  return { ок: false, заметка: 'дашборд не отвечал (код ' + код + '), запущен перезапуск' };
}

function состояниеМашин() {
  const р = { npОнлайн: null, igra2Онлайн: null };
  let вывод = '';
  try { вывод = командаУзла([path.join('штаб', 'вм.js'), 'устройства'], 30000); } catch (_) { return р; }
  for (const строка of вывод.split('\n')) {
    const м = /имя=(\S+).*онлайн=(true|false)/.exec(строка);
    if (!м) continue;
    if (м[1] === 'np-ubuntu') р.npОнлайн = м[2] === 'true';
    if (м[1] === 'igra2') р.igra2Онлайн = м[2] === 'true';
  }
  return р;
}

function читатьJson(имя) {
  return JSON.parse(fs.readFileSync(path.join(__dirname, имя), 'utf8'));
}

function последнееВремя(записи) {
  let макс = '';
  for (const з of записи) {
    const т = з && з['когда точно'];
    if (typeof т === 'string' && т > макс) макс = т;
  }
  return макс;
}

function счётчикиФайлов() {
  const р = { ответов: null, ответПоследний: '', писем: null, письмоПоследнее: '', нуженОтвет: null };
  try {
    const о = Object.values(читатьJson('ответы.json')['ответы'] || {});
    р.ответов = о.length; р.ответПоследний = последнееВремя(о);
  } catch (_) { /* оставляем «нет данных» */ }
  try {
    const п = читатьJson('письма.json')['письма'] || [];
    р.писем = п.length; р.письмоПоследнее = последнееВремя(п);
  } catch (_) { /* оставляем «нет данных» */ }
  try {
    const з = читатьJson('важное.json')['записи'] || [];
    р.нуженОтвет = з.filter((x) => x['вид'] === 'нужен ответ').length;
  } catch (_) { /* оставляем «нет данных» */ }
  return р;
}

function последнийКоммит() {
  try {
    return execFileSync('git', ['log', '-1', '--format=%h'], { cwd: КОРЕНЬ, encoding: 'utf8', timeout: 10000 }).trim();
  } catch (_) { return ''; }
}

// Одной строкой: только строки-статусы («ок   developer»), без счётчиков минут,
// чтобы состояние не менялось каждый проход само по себе.
function ктоМолчит() {
  let вывод = '';
  try { вывод = командаУзла([path.join('штаб', 'кто-молчит.js')], 30000); } catch (_) { return 'не удалось узнать'; }
  const статусы = вывод.split('\n').filter((с) => /^\S/.test(с) === false && /^ {1,3}\S/.test(с) && !/^ {5,}/.test(с)).map((с) => с.trim().replace(/\s+/g, ' '));
  if (/в списке работ пусто/.test(вывод)) return 'в списке работ пусто';
  return статусы.length ? статусы.join('; ') : 'нет данных';
}

function читатьПрошлое() {
  try { return JSON.parse(fs.readFileSync(ФАЙЛ_СОСТОЯНИЯ, 'utf8')); } catch (_) { return null; }
}

function записатьАтомарно(файл, текст) {
  const врем = файл + '.tmp';
  fs.writeFileSync(врем, текст);
  fs.renameSync(врем, файл);
}

function обновитьЗаметку(времяДДММЧЧММ) {
  let сырой;
  try { сырой = fs.readFileSync(ФАЙЛ_В_РАБОТЕ, 'utf8'); } catch (_) { return; }
  let данные;
  try { данные = JSON.parse(сырой); } catch (_) { return; }
  if (typeof данные['заметка'] !== 'string') return;
  const новая = заменитьВремя(данные['заметка'], времяДДММЧЧММ);
  if (новая === данные['заметка']) return;
  данные['заметка'] = новая;
  const хвост = сырой.endsWith('\n') ? '\n' : '';
  записатьАтомарно(ФАЙЛ_В_РАБОТЕ, JSON.stringify(данные, null, 2) + хвост);
}

async function одинПроход() {
  const сейчас = new Date();
  const дашборд = await проверитьДашборд();
  const кодАдреса = await запрос(https, АДРЕС_ИГРЫ, 15000);
  const стало = Object.assign(
    { кодАдреса },
    состояниеМашин(),
    счётчикиФайлов(),
    { коммит: последнийКоммит(), молчат: ктоМолчит() }
  );
  const было = читатьПрошлое();
  записатьАтомарно(ФАЙЛ_СОСТОЯНИЯ, JSON.stringify(стало, null, 2) + '\n');
  обновитьЗаметку(времяСтрокой(сейчас));
  const итог = собратьИтог(было, стало, времяСтрокой(сейчас).slice(6));
  if (!дашборд.ок) итог.текст += '\n' + дашборд.заметка;
  return итог;
}

async function сторожить(минуты) {
  const пауза = Math.max(1, минуты) * 60000;
  for (;;) {
    const итог = await одинПроход();
    if (итог.изменилось) { console.log(итог.текст); process.exit(1); }
    await new Promise((г) => setTimeout(г, пауза));
  }
}

// ---------- самопроверка ----------

function самопроверка() {
  let зелёных = 0;
  let красных = 0;
  // Каждое утверждение: предикат должен быть истинным на хороших данных
  // и ложным на заведомо испорченных — иначе проверка красная.
  function пара(имя, предикат, хорошие, испорченные) {
    let ок = false;
    try { ок = предикат(...хорошие) === true && предикат(...испорченные) === false; } catch (_) { ок = false; }
    if (ок) зелёных++; else { красных++; console.log('КРАСНОЕ: ' + имя); }
  }
  const база = { кодАдреса: 200, npОнлайн: true, igra2Онлайн: true, ответов: 5, ответПоследний: '2026-10-04T10:00:00Z',
    писем: 2, письмоПоследнее: '2026-10-03T10:00:00Z', нуженОтвет: 2, коммит: 'abc1234', молчат: 'ок developer' };
  const без = (а, б) => сравнить(а, б).length === 0;

  пара('нет изменений — пустой список', без, [база, { ...база }], [база, { ...база, коммит: 'zzz' }]);
  пара('код адреса 200→502 замечен', (а, б) => сравнить(а, б).some((с) => /адрес игры/.test(с) && /200 → 502/.test(с)),
    [база, { ...база, кодАдреса: 502 }], [база, { ...база }]);
  пара('новый ответ замечен', (а, б) => сравнить(а, б).some((с) => /ответов владельца/.test(с)),
    [база, { ...база, ответов: 6, ответПоследний: '2026-10-04T11:00:00Z' }], [база, { ...база }]);
  пара('новый коммит замечен', (а, б) => сравнить(а, б).some((с) => /abc1234 → def5678/.test(с)),
    [база, { ...база, коммит: 'def5678' }], [база, { ...база, коммит: 'abc1234' }]);
  пара('нет прошлого файла — изменилось всё', (а, б) => сравнить(а, б).length >= 5,
    [null, база], [база, база]);
  пара('замена времени не портит остальной текст', (исх, рез) => рез === '05.10 01:02' + исх.slice(11),
    ['04.10 22:09. ГОРИТ: всё плохо. Дальше — ещё.', заменитьВремя('04.10 22:09. ГОРИТ: всё плохо. Дальше — ещё.', '05.10 01:02')],
    ['04.10 22:09. один текст', '05.10 01:02. другой текст']);
  пара('заметка без даты не тронута', (исх, рез) => исх === рез,
    ['Просто текст 04.10 22:09.', заменитьВремя('Просто текст 04.10 22:09.', '05.10 01:02')],
    ['Просто текст', 'Другой текст']);
  пара('итог без изменений — одна строка и код 0',
    (а, б) => { const и = собратьИтог(а, б, '22:09'); return и.изменилось === false && !и.текст.includes('\n') && и.текст === 'без изменений 22:09'; },
    [база, { ...база }], [база, { ...база, кодАдреса: 502 }]);
  const упала = { ...база, кодАдреса: 502 };
  пара('ГОРИТ при переходе на ошибку — первой строкой',
    (а, б) => собратьИтог(а, б, '22:09').текст.split('\n')[0].startsWith('ГОРИТ:'),
    [база, упала], [база, { ...база, коммит: 'новый' }]);
  пара('ГОРИТ не повторяется каждый проход, но хвост есть',
    (а, б) => { const и = собратьИтог(а, б, '22:09'); return !и.изменилось && /по-прежнему не открывается/.test(и.текст); },
    [упала, { ...упала }], [база, { ...база }]);
  пара('np-ubuntu не на связи — ГОРИТ',
    (а, б) => /^ГОРИТ:.*np-ubuntu/.test(собратьИтог(а, б, '22:09').текст),
    [база, { ...база, npОнлайн: false }], [база, { ...база, igra2Онлайн: false }]);

  console.log('зелёных ' + зелёных + ', красных ' + красных);
  return красных === 0;
}

// ---------- запуск ----------

async function main() {
  const арг = process.argv.slice(2);
  if (арг.includes('--проверить')) process.exit(самопроверка() ? 0 : 1);
  const и = арг.indexOf('--сторожить');
  if (и !== -1) {
    const минуты = Number(арг[и + 1]);
    await сторожить(Number.isFinite(минуты) && минуты > 0 ? минуты : 10);
    return;
  }
  const итог = await одинПроход();
  console.log(итог.текст);
  process.exit(итог.изменилось ? 1 : 0);
}

main();
