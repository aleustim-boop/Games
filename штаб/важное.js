/*
  Ведёт раздел «Важное»: проставляет время записям и переписывает
  раздел «Ждём слова владельца» в ЗАДАЧИ.md по тем записям, где нужен ответ.

  Зовётся одной короткой строкой:

      node штаб/важное.js

  Записи лежат в штаб/важное.json. Правило то же, что у списков и работ:
  **время не пишется руками**. Появилась запись без поля «появилось» —
  программа ставит текущее время из часов машины и дописывает его в файл.
  Так «появилось вчера» не может оказаться выдумкой.

  Заодно программа проверяет то, что человек забывает: пустые заголовки,
  повторяющиеся ключи, неизвестный вид записи, кнопки без ключа. Ошибку
  показывает словами, а не молча портит страницу.

  Раздел «Ждём слова владельца» в ЗАДАЧИ.md отныне пишет только эта
  программа: источник вопросов к владельцу должен быть один, иначе два
  списка разойдутся и мы вернёмся к тому, с чего начинали.
*/

'use strict';

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ФАЙЛ_ЗАДАЧ = path.join(КОРЕНЬ, 'ЗАДАЧИ.md');
const ФАЙЛ_ЗАПИСЕЙ = path.join(__dirname, 'важное.json');
const ФАЙЛ_ОТВЕТОВ = path.join(__dirname, 'ответы.json');

const ЗАГОЛОВОК_ВОПРОСОВ = '## Ждём слова владельца';
const ЗАГОЛОВОК_ДОЛГОВ = '## Долги команды';
const ИЗВЕСТНЫЕ_ВИДЫ = ['нужен ответ', 'к сведению', 'решено'];

const МЕСЯЦЫ = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
  'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];

function сейчасСловами() {
  const д = new Date();
  const дв = function (ч) { return String(ч).padStart(2, '0'); };
  return д.getDate() + ' ' + МЕСЯЦЫ[д.getMonth()] + ', ' + дв(д.getHours()) + ':' + дв(д.getMinutes());
}

/* ---------------------------------------------------------------------------
   Проверка записей — говорим о бедах словами
--------------------------------------------------------------------------- */

function проверить(записи) {
  const беды = [];
  const ключи = new Set();

  записи.forEach(function (з, номер) {
    const где = 'запись №' + (номер + 1) + ' (' + (з.заголовок || з.ключ || 'без имени') + ')';

    if (!з.ключ) беды.push(где + ': нет поля «ключ» — по нему строится адрес страницы');
    else if (ключи.has(з.ключ)) беды.push(где + ': ключ «' + з.ключ + '» уже занят другой записью');
    else if (!/^[a-zа-яё0-9-]+$/i.test(з.ключ)) беды.push(где + ': в ключе есть пробелы или знаки — оставьте буквы, цифры и дефис');
    else ключи.add(з.ключ);

    if (!з.заголовок) беды.push(где + ': нет заголовка, а он должен быть понятен без открытия');
    else if (з.заголовок.length > 95) беды.push(где + ': заголовок длиннее 95 знаков — на телефоне он не прочитается одним взглядом');

    if (!з.суть) беды.push(где + ': нет поля «суть» — двух-трёх предложений, которые видно в списке');

    if (з.вид && ИЗВЕСТНЫЕ_ВИДЫ.indexOf(з.вид) < 0) {
      беды.push(где + ': вид «' + з.вид + '» неизвестен, бывают только: ' + ИЗВЕСТНЫЕ_ВИДЫ.join(', '));
    }

    if (!з.подробно && !з.особая) {
      беды.push(где + ': нет ни «подробно», ни «особая» — страница записи выйдет пустой');
    }

    if (Array.isArray(з.кнопки)) {
      for (const к of з.кнопки) {
        if (!к.ключ || !к.имя) беды.push(где + ': у кнопки нет «ключ» или «имя»');
      }
    }
  });

  return беды;
}

/* ---------------------------------------------------------------------------
   Раздел «Ждём слова владельца» в ЗАДАЧИ.md
--------------------------------------------------------------------------- */

function границыРаздела(текст, заголовок) {
  const начало = текст.indexOf(заголовок);
  if (начало < 0) return null;
  const дальше = текст.indexOf('\n## ', начало + 5);
  return { начало: начало, конец: дальше < 0 ? текст.length : дальше + 1 };
}

function собратьРаздел(вопросы, ответы) {
  let раздел = ЗАГОЛОВОК_ВОПРОСОВ + '\n\n'
    + 'Это не долг команды и не очередь: работы тут на несколько строк, но решать\n'
    + 'должен владелец. Раздел ведёт `node штаб/важное.js` по файлу `штаб/важное.json`,\n'
    + 'он же показывает эти вопросы на дашборде в разделе «Важное».\n\n';

  if (!вопросы.length) {
    раздел += '**Открытых вопросов нет.**\n\n';
    return раздел;
  }

  раздел += '| Вопрос владельцу | Появился | Ответ |\n|---|---|---|\n';
  for (const в of вопросы) {
    const ответ = ответы[в.ключ];
    раздел += '| **' + в.заголовок + '** | ' + (в.появилось || '—') + ' | '
      + (ответ ? 'выбрано: ' + (ответ.имя || ответ.кнопка) + ' (' + (ответ.когда || '') + ')' : 'ждём')
      + ' |\n';
  }
  return раздел + '\n';
}

function прочитатьОтветы() {
  try {
    const данные = JSON.parse(fs.readFileSync(ФАЙЛ_ОТВЕТОВ, 'utf8'));
    return данные && данные.ответы ? данные.ответы : {};
  } catch (ошибка) {
    return {};
  }
}

/* ---------------------------------------------------------------------------
   Главное
--------------------------------------------------------------------------- */

if (!fs.existsSync(ФАЙЛ_ЗАПИСЕЙ)) {
  console.log('нет файла ' + ФАЙЛ_ЗАПИСЕЙ + ' — напишите его и позовите снова');
  process.exit(1);
}

let данные;
try {
  данные = JSON.parse(fs.readFileSync(ФАЙЛ_ЗАПИСЕЙ, 'utf8'));
} catch (ошибка) {
  console.log('в штаб/важное.json сломана разметка: ' + ошибка.message);
  process.exit(1);
}

const записи = Array.isArray(данные.записи) ? данные.записи : [];

const беды = проверить(записи);
if (беды.length) {
  console.log('записи не в порядке, ничего не менял:');
  for (const б of беды) console.log('  · ' + б);
  process.exit(1);
}

// Время появления — из часов машины, один раз на запись.
let дописали = 0;
for (const з of записи) {
  if (!з.появилось) { з.появилось = сейчасСловами(); дописали += 1; }
}
if (дописали) fs.writeFileSync(ФАЙЛ_ЗАПИСЕЙ, JSON.stringify(данные, null, 2) + '\n', 'utf8');

// Раздел в ЗАДАЧИ.md — по записям, где ждём ответа.
const вопросы = записи.filter(function (з) { return з.вид === 'нужен ответ'; });
const раздел = собратьРаздел(вопросы, прочитатьОтветы());

let текст = fs.readFileSync(ФАЙЛ_ЗАДАЧ, 'utf8');
const место = границыРаздела(текст, ЗАГОЛОВОК_ВОПРОСОВ);
if (место) {
  текст = текст.slice(0, место.начало) + раздел + текст.slice(место.конец);
} else {
  const куда = текст.indexOf(ЗАГОЛОВОК_ДОЛГОВ);
  текст = куда >= 0 ? текст.slice(0, куда) + раздел + текст.slice(куда) : текст + '\n' + раздел;
}
fs.writeFileSync(ФАЙЛ_ЗАДАЧ, текст, 'utf8');

const поВидам = {};
for (const з of записи) поВидам[з.вид || 'к сведению'] = (поВидам[з.вид || 'к сведению'] || 0) + 1;

console.log('записей: ' + записи.length + ' (' + Object.keys(поВидам).map(function (в) { return в + ' — ' + поВидам[в]; }).join(', ') + ')');
if (дописали) console.log('проставлено время у новых записей: ' + дописали + ' (' + сейчасСловами() + ')');
console.log('раздел «Ждём слова владельца» в ЗАДАЧИ.md переписан');
