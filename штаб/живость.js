/* Живость: дашборд узнаёт сам, работают ли исполнители и не протух ли список.

   Зачем этот файл появился. Дашборд ни разу не соврал сам — он честно вычитал
   одно время из другого. Врал источник: время в список клал человек. Дважды за
   один день владелец ловил неправду — выдуманную ночь работы и «идёт 11 часов»
   у давно сданного дела. Значит чинить надо не показ, а добычу.

   Здесь два факта, которые можно добыть с диска и нельзя выдумать:

   1. ЖИВ ЛИ ИСПОЛНИТЕЛЬ. У каждого запущенного исполнителя есть файл записей
      в папке задач:
          %TEMP%\claude\<папка проекта>\<номер сессии>\tasks\<номер задачи>.output
      Этот файл растёт, пока исполнитель работает. Поэтому время его последней
      правки — настоящий признак: свежее двух минут — работает, десять минут
      тишины — скорее всего встал.

      ВАЖНО: содержимое этих файлов не читается ни строчкой. Они бывают по
      несколько мегабайт, и держать их в памяти нельзя. Берём только дату
      правки и размер — это отдаёт сама файловая система, файл при этом даже
      не открывается.

   2. КОГДА СПИСОК ПРАВИЛИ. Время правки штаб/в-работе.json и ЗАДАЧИ.md.
      Именно этого не хватало: владелец не мог отличить «ничего не происходит»
      от «мне забыли сказать».

   Ничего не выдумываем: не нашли папку — так и говорим, а не показываем ноль. */

'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');

const КОРЕНЬ = path.resolve(path.join(__dirname, '..'));
const ФАЙЛ_РАБОТ = path.join(__dirname, 'в-работе.json');
const ФАЙЛ_ЗАДАЧ = path.join(КОРЕНЬ, 'ЗАДАЧИ.md');

const МИНУТА = 60 * 1000;

/* Пороги. Названы словами, потому что их придётся подкручивать по жизни. */
const СРОК_РАБОТАЕТ = 2;   // минут: свежее — точно пишет прямо сейчас
const СРОК_ВСТАЛ = 10;     // минут тишины: дальше считаем, что исполнитель встал
const СРОК_УСТАРЕЛ = 30;   // минут: старше — списку верить нельзя

/* ---------------------------------------------------------------------------
   Мелочи про время
--------------------------------------------------------------------------- */

function минутНазад(дата, сейчас) {
  if (!дата) return null;
  const минут = Math.round((сейчас - дата.getTime()) / МИНУТА);
  return минут < 0 ? 0 : минут;
}

/** «7 мин», «2 ч 10 мин», «3 дн» — так, как сказал бы человек. */
function словамиДлительность(минут) {
  if (минут === null || минут === undefined) return null;
  if (минут < 60) return минут + ' мин';
  const часов = Math.floor(минут / 60);
  const остаток = минут % 60;
  if (часов < 24) return остаток ? часов + ' ч ' + остаток + ' мин' : часов + ' ч';
  return Math.floor(часов / 24) + ' дн';
}

/** Время правки файла. Нет файла — честный null, а не «сейчас». */
function времяПравки(путь) {
  try {
    return fs.statSync(путь).mtime;
  } catch (ошибка) {
    return null;
  }
}

/* ---------------------------------------------------------------------------
   1. Записи исполнителей
--------------------------------------------------------------------------- */

/**
 * Имя папки, в которой лежат сессии этого проекта.
 * Путь проекта превращается в имя папки заменой двоеточия и косых на дефис,
 * а буква диска становится строчной: D:\Claud\Games → d--Claud-Games.
 */
function имяПапкиПроекта(корень) {
  const заменено = String(корень).replace(/[:\\/]/g, '-');
  return заменено.charAt(0).toLowerCase() + заменено.slice(1);
}

/**
 * Что лежит в папке задач одной сессии: имя, дата правки, размер.
 * Файлы не открываются — спрашивается только карточка файла у системы.
 */
function записиПапки(путьПапки) {
  let имена;
  try {
    имена = fs.readdirSync(путьПапки);
  } catch (ошибка) {
    return []; // папки нет или её не пускают — это не беда, просто пусто
  }

  const записи = [];
  for (const имя of имена) {
    if (!имя.endsWith('.output')) continue;
    let карточка;
    try {
      карточка = fs.statSync(path.join(путьПапки, имя));
    } catch (ошибка) {
      continue; // файл исчез между списком и опросом — бывает, пропускаем
    }
    if (!карточка.isFile()) continue;
    записи.push({
      имя: имя.slice(0, имя.length - '.output'.length),
      изменён: карточка.mtime,
      размер: карточка.size
    });
  }

  записи.sort(function (а, б) { return б.изменён - а.изменён; });
  return записи;
}

/**
 * Записи самой свежей сессии. Сессий на диске десятки, живая — одна:
 * та, в которой только что кто-то писал.
 */
function записиИсполнителей() {
  const корневая = path.join(os.tmpdir(), 'claude', имяПапкиПроекта(КОРЕНЬ));

  let сессии;
  try {
    сессии = fs.readdirSync(корневая);
  } catch (ошибка) {
    return {
      найдена: false, папка: корневая, записи: [],
      беда: 'папки с записями исполнителей нет на этом компьютере — живость показать нечем'
    };
  }

  let лучшая = null;
  for (const сессия of сессии) {
    const записи = записиПапки(path.join(корневая, сессия, 'tasks'));
    if (!записи.length) continue;
    if (!лучшая || записи[0].изменён > лучшая.записи[0].изменён) {
      лучшая = { папка: path.join(корневая, сессия, 'tasks'), записи: записи };
    }
  }

  if (!лучшая) {
    return {
      найдена: false, папка: корневая, записи: [],
      беда: 'в папках сессий нет ни одной записи исполнителя — похоже, никого не запускали'
    };
  }

  return {
    найдена: true,
    папка: лучшая.папка,
    всего: лучшая.записи.length,
    // Дальше первых полусотни смотреть незачем: они отсортированы по свежести.
    записи: лучшая.записи.slice(0, 50),
    беда: null
  };
}

/* ---------------------------------------------------------------------------
   2. Связь записи с работой
--------------------------------------------------------------------------- */

/** Работы, которые штаб записал в штаб/в-работе.json. */
function читатьРаботы() {
  let текст;
  try {
    текст = fs.readFileSync(ФАЙЛ_РАБОТ, 'utf8');
  } catch (ошибка) {
    return { работы: [], беда: 'файл штаб/в-работе.json не читается — сверить работы с записями не с чем' };
  }
  try {
    const данные = JSON.parse(текст);
    return { работы: Array.isArray(данные.работы) ? данные.работы : [], беда: null };
  } catch (ошибка) {
    return { работы: [], беда: 'в штаб/в-работе.json сломана разметка: ' + ошибка.message };
  }
}

/** Одинаковый ли это текст задачи: без звёздочек, кавычек и лишних пробелов. */
function ключТекста(текст) {
  return String(текст === null || текст === undefined ? '' : текст)
    .replace(/\*\*/g, '')
    .replace(/`/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

/** Ищем запись по номеру задачи. Хватает первых знаков — штабу удобнее. */
function записьПоНомеру(записи, номер) {
  const ключ = String(номер || '').trim().toLowerCase();
  if (ключ.length < 4) return null;
  for (const запись of записи) {
    const имя = запись.имя.toLowerCase();
    if (имя.startsWith(ключ) || ключ.startsWith(имя)) return запись;
  }
  return null;
}

/** Признак по времени последней записи: работает, притих или встал. */
function признакПоВремени(запись, сейчас) {
  const минут = минутНазад(запись.изменён, сейчас);
  if (минут <= СРОК_РАБОТАЕТ) {
    return {
      состояние: запись.размер === 0 ? 'тихо' : 'работает',
      минут: минут,
      слова: запись.размер === 0 ? 'запущен, но не написал ещё ни строчки' : 'работает'
    };
  }
  if (минут < СРОК_ВСТАЛ) {
    return { состояние: 'тихо', минут: минут, слова: 'тихо ' + словамиДлительность(минут) };
  }
  return { состояние: 'встал', минут: минут, слова: 'молчит ' + словамиДлительность(минут) };
}

/**
 * Главное наружу: кто из записанных работ подаёт признаки жизни.
 * Работы берутся из штаб/в-работе.json, признак — из папки задач.
 */
function живостьИсполнителей(сейчас) {
  const момент = сейчас || Date.now();
  const сведения = записиИсполнителей();
  const списокРабот = читатьРаботы();

  const занятые = new Set();
  const работы = списокРабот.работы.map(function (р) {
    const строка = {
      что: р.что || '',
      кто: р.кто || '',
      номер: р.задача ? String(р.задача) : null,
      состояние: 'не-связана',
      слова: 'связь с записями не настроена',
      минут: null
    };

    if (!сведения.найдена) {
      строка.состояние = 'неизвестно';
      строка.слова = 'записей исполнителей на этом компьютере нет';
      return строка;
    }
    if (!строка.номер) return строка;

    const запись = записьПоНомеру(сведения.записи, строка.номер);
    if (!запись) {
      строка.состояние = 'нет-записи';
      строка.слова = 'записей с таким номером не нашлось';
      return строка;
    }

    занятые.add(запись.имя);
    const признак = признакПоВремени(запись, момент);
    строка.состояние = признак.состояние;
    строка.слова = признак.слова;
    строка.минут = признак.минут;
    return строка;
  });

  // Записи, которые растут прямо сейчас, но ни к одной работе не привязаны.
  // Это подсказка штабу: кто-то работает, а в списке его нет.
  const прочиеЖивые = сведения.записи.filter(function (з) {
    if (занятые.has(з.имя)) return false;
    return минутНазад(з.изменён, момент) <= СРОК_РАБОТАЕТ;
  }).map(function (з) {
    return { имя: з.имя, минут: минутНазад(з.изменён, момент) };
  });

  return {
    найдена: сведения.найдена,
    папка: сведения.папка,
    всегоЗаписей: сведения.всего || 0,
    работы: работы,
    прочиеЖивые: прочиеЖивые,
    беда: сведения.беда || списокРабот.беда
  };
}

/* ---------------------------------------------------------------------------
   3. Свежесть самого списка
--------------------------------------------------------------------------- */

/**
 * Когда список правили в последний раз. Берём то из двух файлов, что новее:
 * штаб пишет либо json, либо сам ЗАДАЧИ.md.
 */
function свежестьСписка(сейчас) {
  const момент = сейчас || Date.now();
  const вРаботе = времяПравки(ФАЙЛ_РАБОТ);
  const задачи = времяПравки(ФАЙЛ_ЗАДАЧ);

  let самое = null;
  if (вРаботе && задачи) самое = вРаботе > задачи ? вРаботе : задачи;
  else самое = вРаботе || задачи;

  const минут = минутНазад(самое, момент);
  return {
    есть: Boolean(самое),
    вРаботе: вРаботе,
    задачи: задачи,
    самоеСвежее: самое,
    минут: минут,
    давность: словамиДлительность(минут),
    устарел: минут !== null && минут > СРОК_УСТАРЕЛ
  };
}

module.exports = {
  живостьИсполнителей: живостьИсполнителей,
  свежестьСписка: свежестьСписка,
  ключТекста: ключТекста,
  словамиДлительность: словамиДлительность,
  // наружу для проверок
  имяПапкиПроекта: имяПапкиПроекта,
  записиПапки: записиПапки,
  записиИсполнителей: записиИсполнителей,
  признакПоВремени: признакПоВремени,
  ПОРОГИ: { работает: СРОК_РАБОТАЕТ, встал: СРОК_ВСТАЛ, устарел: СРОК_УСТАРЕЛ }
};
