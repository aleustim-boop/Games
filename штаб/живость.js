/** Работы, которые штаб записал в штаб/в-работе.json. */
function читатьРаботы() {
  let текст;
  try {
    текст = fs.readFileSync(ФАЙЛ_РАБОТ, 'utf8');
  } catch (ошибка) {
    return { работы: [], беда: 'файл штаб/в-работе.json не читается — сверить работы с записями не с чем' };
  }
  try {
    const данные = JSON.parse(текст);
    return { работы: Array.isArray(данные.работы) ? данные.работы : [], беда: null };
  } catch (ошибка) {
    return { работы: [], беда: 'в штаб/в-работе.json сломана разметка: ' + ошибка.message };
  }
}

/** Одинаковый ли это текст задачи: без звёздочек, кавычек и лишних пробелов. */
function ключТекста(текст) {
  return String(текст === null || текст === undefined ? '' : текст)
    .replace(/\*\*/g, '')
    .replace(/`/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

/** Ищем запись по номеру задачи. Хватает первых знаков — штабу удобнее. */
function записьПоНомеру(записи, номер) {
  const ключ = String(номер || '').trim().toLowerCase();
  if (ключ.length < 4) return null;
  for (const запись of записи) {
    const имя = запись.имя.toLowerCase();
    if (имя.startsWith(ключ) || ключ.startsWith(имя)) return запись;
  }
  return null;
}

/** Признак по времени последней записи: работает, притих или встал. */
function признакПоВремени(запись, сейчас) {
  const минут = минутНазад(запись.изменён, сейчас);
  if (минут <= СРОК_РАБОТАЕТ) {
    return {
      состояние: запись.размер === 0 ? 'тихо' : 'работает',
      минут: минут,
      слова: запись.размер === 0 ? 'запущен, но не написал ещё ни строчки' : 'работает'
    };
  }
  if (минут < СРОК_ВСТАЛ) {
    return { состояние: 'тихо', минут: минут, слова: 'тихо ' + словамиДлительность(минут) };
  }
  return { состояние: 'встал', минут: минут, слова: 'молчит ' + словамиДлительность(минут) };
}

/**
 * Главное наружу: кто из записанных работ подаёт признаки жизни.
 * Работы берутся из штаб/в-работе.json, признак — из файлов записей.
 *
 * Второй довод — только для проверки, как в штаб/кто-молчит.js: подставные
 * записи и работы. Настоящие данные штаба (он правит их прямо во время
 * работы) тогда не читаются вовсе и не могут покрасить проверку.
 */
function живостьИсполнителей(сейчас, подделка) {
  const момент = сейчас || Date.now();
  const сведения = подделка && подделка.записи
    ? { найдена: true, папка: '(подделка)', всего: подделка.записи.length, записи: подделка.записи, беда: null }
    : записиИсполнителей();
  const списокРабот = подделка && подделка.работы
    ? { работы: подделка.работы, беда: null }
    : читатьРаботы();

  const занятые = new Set();
  const работы = списокРабот.работы.map(function (р) {
    const строка = {
      что: р.что || '',
      кто: р.кто || '',
      номер: р.задача ? String(р.задача) : null,
      состояние: 'не-связана',
      слова: 'связь с записями не настроена',
      минут: null
    };

    if (!сведения.найдена) {
      строка.состояние = 'неизвестно';
      строка.слова = 'записей исполнителей на этом компьютере нет';
      return строка;
    }
    if (!строка.номер) return строка;

    const запись = записьПоНомеру(сведения.записи, строка.номер);
    if (!запись) {
      строка.состояние = 'нет-записи';
      строка.слова = 'записей с таким номером не нашлось';
      return строка;
    }

    занятые.add(запись.имя);
    const признак = признакПоВремени(запись, момент);
    строка.состояние = признак.состояние;
    строка.слова = признак.слова;
    строка.минут = признак.минут;
    return строка;
  });

  // Исполнители, чьи записи растут прямо сейчас, но ни к одной работе не
  // привязаны: кто-то работает, а в списке его нет. Фоновые команды штаба
  // сюда не попадают — они не исполнители, и в списке работ им не место.
  const прочиеЖивые = [];
  for (const з of сведения.записи) {
    if (!з.исполнитель || занятые.has(з.имя)) continue;
    if (минутНазад(з.изменён, момент) > СРОК_РАБОТАЕТ) continue;
    // Подставные записи могут принести роль и задание сразу, живые — путь к описанию.
    const описание = з.описание ? описаниеИсполнителя(з.описание) : { роль: з.роль || null, задание: з.задание || null };
    // Исполнители — только роли команды из CLAUDE.md. Вспомогательные агенты
    // штаба (Explore, general-purpose) работу из списка не делают, и полосу
    // красить не должны. Роль не узнали — тоже не исполнитель: гадать нельзя.
    if (!описание.роль || !Object.prototype.hasOwnProperty.call(РОЛИ, описание.роль)) continue;
    прочиеЖивые.push({
      имя: з.имя,
      минут: минутНазад(з.изменён, момент),
      роль: РОЛИ[описание.роль],
      задание: описание.задание
    });
  }

  return {
    найдена: сведения.найдена,
    папка: сведения.папка,
    всегоЗаписей: сведения.всего || 0,
    работы: работы,
    прочиеЖивые: прочиеЖивые,
    бедаСписка: списокРабот.беда,
    беда: сведения.беда || списокРабот.беда
  };
}

/**
 * Расходится ли список «в работе» с правдой.
 *
 * Зачем так, а не по времени правки файла. Раньше красная полоса мерила,
 * когда штаб трогал список. Теперь дашборд сам пересобирает список раз в
 * пять минут, и время правки всегда свежее — полоса молчала бы и тогда,
 * когда список врёт. Поэтому мерим не возраст, а расхождение с фактами:
 *
 *   - в списке есть работа, а файл её исполнителя молчит дольше десяти
 *     минут (он закончил, встал или ждёт очень долгую команду — по файлу
 *     это не различить, решает человек);
 *   - в списке есть работа, а файла с её номером нет вовсе;
 *   - растёт файл исполнителя, которого в списке нет;
 *   - сам список не читается.
 *
 * Возвращает перечень расхождений словами; пустой перечень — список сходится.
 */
function расхожденияСписка(ктоЖив) {
  const итог = { можноСверить: false, беда: null, список: [], сверено: 0, безНомера: 0 };

  if (!ктоЖив) {
    итог.беда = 'сведений о живости нет';
    return итог;
  }
  if (ктоЖив.бедаСписка) {
    итог.можноСверить = true;
    итог.список.push({ вид: 'список не читается', кто: 'штаб', что: 'штаб/в-работе.json', слова: ктоЖив.бедаСписка });
    return итог;
  }
  if (!ктоЖив.найдена) {
    итог.беда = ктоЖив.беда || 'записей исполнителей не нашлось';
    return итог;
  }

  итог.можноСверить = true;
  for (const р of ктоЖив.работы) {
    if (р.состояние === 'встал') {
      итог.список.push({
        вид: 'молчит', кто: р.кто, что: р.что,
        слова: 'молчит ' + словамиДлительность(р.минут) + ' — закончил или встал, а в списке значится в работе'
      });
    } else if (р.состояние === 'нет-записи') {
      итог.список.push({
        вид: 'нет записи', кто: р.кто, что: р.что,
        слова: 'файла записей с номером ' + р.номер + ' нет — исполнителя, похоже, уже нет'
      });
    } else if (р.состояние === 'не-связана') {
      итог.безНомера += 1;
    } else {
      итог.сверено += 1;
    }
  }

  for (const ж of ктоЖив.прочиеЖивые || []) {
    итог.список.push({
      вид: 'нет в списке',
      кто: ж.роль || 'исполнитель',
      что: ж.задание || ('запись ' + ж.имя),
      слова: 'работает прямо сейчас, а в списке «в работе» его нет'
    });
  }

  return итог;
}

/* ---------------------------------------------------------------------------
   3. Свежесть самого списка
--------------------------------------------------------------------------- */

/**
 * Когда список правили в последний раз. Берём то из двух файлов, что новее:
 * штаб пишет либо json, либо сам ЗАДАЧИ.md.
 */
function свежестьСписка(сейчас) {
  const момент = сейчас || Date.now();
  const вРаботе = времяПравки(ФАЙЛ_РАБОТ);
  const задачи = времяПравки(ФАЙЛ_ЗАДАЧ);

  let самое = null;
  if (вРаботе && задачи) самое = вРаботе > задачи ? вРаботе : задачи;
  else самое = вРаботе || задачи;

  const минут = минутНазад(самое, момент);
  return {
    есть: Boolean(самое),
    вРаботе: вРаботе,
    задачи: задачи,
    самоеСвежее: самое,
    минут: минут,
    давность: словамиДлительность(минут),
    устарел: минут !== null && минут > СРОК_УСТАРЕЛ
  };
}

