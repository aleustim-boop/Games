const МИНУТА = 60 * 1000;

/* Пороги. Названы словами, потому что их придётся подкручивать по жизни. */
const СРОК_РАБОТАЕТ = 2;   // минут: свежее — точно пишет прямо сейчас
const СРОК_ВСТАЛ = 10;     // минут тишины: дальше считаем, что исполнитель встал
const СРОК_УСТАРЕЛ = 30;   // минут: старше — списку верить нельзя

