/**
 * Имя папки, в которой лежат сессии этого проекта.
 * Путь проекта превращается в имя папки заменой двоеточия и косых на дефис,
 * а буква диска становится строчной: D:\Claud\Games → d--Claud-Games.
 */
function имяПапкиПроекта(корень) {
  const заменено = String(корень).replace(/[:\\/]/g, '-');
  return заменено.charAt(0).toLowerCase() + заменено.slice(1);
}

/**
 * Что лежит в папке задач одной сессии: имя, дата правки, размер.
 * Файлы не открываются — спрашивается только карточка файла у системы.
 */
function записиПапки(путьПапки) {
  let имена;
  try {
    имена = fs.readdirSync(путьПапки);
  } catch (ошибка) {
    return []; // папки нет или её не пускают — это не беда, просто пусто
  }

  const записи = [];
  for (const имя of имена) {
    if (!имя.endsWith('.output')) continue;
    let карточка;
    try {
      карточка = fs.statSync(path.join(путьПапки, имя));
    } catch (ошибка) {
      continue; // файл исчез между списком и опросом — бывает, пропускаем
    }
    if (!карточка.isFile()) continue;
    записи.push({
      имя: имя.slice(0, имя.length - '.output'.length),
      изменён: карточка.mtime,
      размер: карточка.size,
      исполнитель: false,
      описание: null
    });
  }

  записи.sort(function (а, б) { return б.изменён - а.изменён; });
  return записи;
}

/**
 * Крошечное описание исполнителя: его роль и заголовок задания.
 * Не прочиталось — не беда, покажем номер.
 */
function описаниеИсполнителя(путьОписания) {
  try {
    const данные = JSON.parse(fs.readFileSync(путьОписания, 'utf8'));
    return {
      роль: данные && данные.agentType ? String(данные.agentType) : null,
      задание: данные && данные.description ? String(данные.description) : null
    };
  } catch (ошибка) {
    return { роль: null, задание: null };
  }
}

/**
 * Записи исполнителей в профиле: subagents\agent-<номер>.jsonl.
 * Как и в папке задач, файл не открывается — берётся только его карточка.
 */
function записиПрофиля(путьПапки) {
  let имена;
  try {
    имена = fs.readdirSync(путьПапки);
  } catch (ошибка) {
    return []; // исполнителей в этой сессии не запускали — пусто
  }

  const записи = [];
  for (const имя of имена) {
    if (!имя.startsWith('agent-') || !имя.endsWith('.jsonl')) continue;
    const номер = имя.slice('agent-'.length, имя.length - '.jsonl'.length);
    let карточка;
    try {
      карточка = fs.statSync(path.join(путьПапки, имя));
    } catch (ошибка) {
      continue;
    }
    if (!карточка.isFile()) continue;
    // Описание не читаем сразу: исполнителей в профиле сотни, а на
    // странице нужны единицы — те, кто работает без записи в списке.
    записи.push({
      имя: номер,
      изменён: карточка.mtime,
      размер: карточка.size,
      исполнитель: true,
      описание: path.join(путьПапки, 'agent-' + номер + '.meta.json')
    });
  }
  return записи;
}

/**
 * Одна задача может лежать в обоих местах. Тогда берём то, что свежее
 * и больше: живой файл один, второй — пустышка.
 */
function слитьЗаписи(изЗадач, изПрофиля) {
  const поНомеру = new Map();
  for (const з of изЗадач) поНомеру.set(з.имя, з);
  for (const з of изПрофиля) {
    const было = поНомеру.get(з.имя);
    if (!было) {
      поНомеру.set(з.имя, з);
      continue;
    }
    поНомеру.set(з.имя, {
      имя: з.имя,
      изменён: з.изменён > было.изменён ? з.изменён : было.изменён,
      размер: Math.max(з.размер, было.размер),
      исполнитель: true,
      описание: з.описание
    });
  }
  const записи = Array.from(поНомеру.values());
  записи.sort(function (а, б) { return б.изменён - а.изменён; });
  return записи;
}

/** Имена папок внутри папки. Нет папки — пустой список. */
function папкиВнутри(путь) {
  try {
    return fs.readdirSync(путь, { withFileTypes: true })
      .filter(function (з) { return з.isDirectory(); })
      .map(function (з) { return з.name; });
  } catch (ошибка) {
    return [];
  }
}

/**
 * Записи всех сессий проекта разом, самые свежие первыми.
 *
 * Раньше бралась одна «самая свежая» сессия. Но сессия штаба меняется при
 * каждом его перезапуске, а исполнитель, запущенный до перезапуска, пишет
 * в папку прежней сессии. Поэтому ищем по всем: номер задачи случайный и
 * длинный, спутать чужую запись с нужной нельзя, а при совпадении первых
 * знаков побеждает самая свежая — она стоит в начале списка.
 */
function записиИсполнителей() {
  const имяПроекта = имяПапкиПроекта(КОРЕНЬ);
  const корневая = path.join(os.tmpdir(), 'claude', имяПроекта);
  const корневаяПрофиля = path.join(ПРОФИЛЬ, 'projects', имяПроекта);

  const сессии = new Set(папкиВнутри(корневая).concat(папкиВнутри(корневаяПрофиля)));
  if (!сессии.size) {
    return {
      найдена: false, папка: корневая, записи: [],
      беда: 'папки с записями исполнителей нет на этом компьютере — живость показать нечем'
    };
  }

  let записи = [];
  for (const сессия of сессии) {
    записи = записи.concat(слитьЗаписи(
      записиПапки(path.join(корневая, сессия, 'tasks')),
      записиПрофиля(path.join(корневаяПрофиля, сессия, 'subagents'))
    ));
  }
  записи.sort(function (а, б) { return б.изменён - а.изменён; });

  if (!записи.length) {
    return {
      найдена: false, папка: корневая, записи: [],
      беда: 'в папках сессий нет ни одной записи исполнителя — похоже, никого не запускали'
    };
  }

  return {
    найдена: true,
    папка: корневаяПрофиля,
    всего: записи.length,
    записи: записи,
    беда: null
  };
}

