function минутНазад(дата, сейчас) {
  if (!дата) return null;
  const минут = Math.round((сейчас - дата.getTime()) / МИНУТА);
  return минут < 0 ? 0 : минут;
}

/** «7 мин», «2 ч 10 мин», «3 дн» — так, как сказал бы человек. */
function словамиДлительность(минут) {
  if (минут === null || минут === undefined) return null;
  if (минут < 60) return минут + ' мин';
  const часов = Math.floor(минут / 60);
  const остаток = минут % 60;
  if (часов < 24) return остаток ? часов + ' ч ' + остаток + ' мин' : часов + ' ч';
  return Math.floor(часов / 24) + ' дн';
}

/**
 * Поле «начато» в штаб/в-работе.json → дата. Не разобрали — null.
 *
 * Новые записи хранят дату и время: «2026-09-10 23:50». Раньше хранили
 * только «23:50», и после полуночи вчерашняя работа получала сегодняшнюю
 * дату, а «идёт N мин» врало. Старые «ЧЧ:ММ» читаются как сегодняшние,
 * а если такое время сегодня ещё не наступило — как вчерашние: работа
 * не может начаться в будущем. Понимает и полную запись ISO (с «T» и поясом).
 */
function разобратьНачато(текст, сейчас) {
  const момент = сейчас || Date.now();
  const строка = String(текст === null || текст === undefined ? '' : текст).trim();
  if (!строка) return null;
  const часы = /^(\d{1,2}):(\d{2})$/.exec(строка);
  if (часы) {
    const д = new Date(момент);
    const дата = new Date(д.getFullYear(), д.getMonth(), д.getDate(), Number(часы[1]), Number(часы[2]));
    if (дата.getTime() > момент + МИНУТА) дата.setDate(дата.getDate() - 1);
    return isNaN(дата.getTime()) ? null : дата;
  }
  const полная = /^(\d{4})-(\d{2})-(\d{2})[ T](\d{1,2}):(\d{2})$/.exec(строка);
  if (полная) {
    const дата = new Date(Number(полная[1]), Number(полная[2]) - 1, Number(полная[3]), Number(полная[4]), Number(полная[5]));
    return isNaN(дата.getTime()) ? null : дата;
  }
  const любая = new Date(строка);
  return isNaN(любая.getTime()) ? null : любая;
}

/** Дата → «2026-09-10 23:50»: так «начато» пишется в штаб/в-работе.json. */
function начатоЗаписью(дата) {
  const дв = function (ч) { return String(ч).padStart(2, '0'); };
  return дата.getFullYear() + '-' + дв(дата.getMonth() + 1) + '-' + дв(дата.getDate())
    + ' ' + дв(дата.getHours()) + ':' + дв(дата.getMinutes());
}

/** Время правки файла. Нет файла — честный null, а не «сейчас». */
function времяПравки(путь) {
  try {
    return fs.statSync(путь).mtime;
  } catch (ошибка) {
    return null;
  }
}

