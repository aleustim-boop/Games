async function собратьВсё() {
  const публикации = await изХолодильника('публикации', 8000, function () { return собратьПубликации(); });
  const задачи = await изХолодильника('задачи', 4000, function () { return разобратьЗадачи(); });
  const службы = await изХолодильника('службы', 12000, состояниеСлужб);

  // Сайт спрашивать дорого и он в интернете, поэтому реже и с запасным ответом.
  let сайт;
  try {
    сайт = await изХолодильника('сайт', 60000, сверкаССайтом);
  } catch (ошибка) {
    сайт = { доступен: false, беда: 'сайт не ответил', расхождения: [], версии: [] };
  }

  // Живость в холодильник не кладём нарочно: это самое скоропортящееся, что
  // есть на странице, а стоит она пару миллисекунд — только опрос карточек
  // файлов, без чтения их содержимого.
  const ктоЖив = живость.живостьИсполнителей();
  const свежестьСписка = живость.свежестьСписка();
  // Сходится ли список «в работе» с фактами — по этому краснеет верхняя полоса.
  const расхождения = живость.расхожденияСписка(ктоЖив);

  /* Простой исполнителей. Порог для владельца — час: получасовая тишина у
     нас обычное дело, а час без единой записи уже значит, что человеку
     нечего делать. Второй довод «false» — смотреть, но следов не писать:
     эту страницу браузер спрашивает по многу раз в минуту. */
  const простой = сторожПростоя.собрать(60, false);

  // Привязываем признак жизни к карточкам «в работе». Совпадение по тексту
  // надёжно: и таблицу в ЗАДАЧИ.md, и json пишет одна программа в-работе.js.
  const поТексту = new Map();
  for (const работа of ктоЖив.работы) поТексту.set(живость.ключТекста(работа.что), работа);
  for (const задача of задачи.вРаботе) {
    задача.живость = поТексту.get(живость.ключТекста(задача.что)) || null;
  }

  // Сторож от забывчивости: за день много записей git, а очередь не тронута.
  // Ровно так и вышло, что владелец увидел девять пунктов, из которых пять
  // были давно сделаны.
  let сторожОчереди = null;
  try {
    const когдаПравили = fs.statSync(path.join(__dirname, 'списки.json')).mtime;
    сторожОчереди = сделано.очередьНеДвигалась(публикации.сегодня, когдаПравили);
  } catch (ошибка) { /* файла списков нет — сторожить нечего */ }

  return {
    собрано: new Date(),
    публикации: публикации,
    задачи: задачи,
    исполнители: ктоЖив,
    свежесть: свежестьСписка,
    расхождения: расхождения,
    простой: простой,
    сторожОчереди: сторожОчереди,
    службы: службы,
    сайт: сайт
  };
}

