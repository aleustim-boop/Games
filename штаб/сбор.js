/* ---------------------------------------------------------------------------
   Маленький «холодильник»: не дёргать git и сайт на каждый запрос браузера.
   У каждого вида данных свой срок годности — сайт спрашивать дорого, файл
   ЗАДАЧИ.md читать дёшево.
--------------------------------------------------------------------------- */
const холодильник = new Map();

async function изХолодильника(имя, срокМс, добыть) {
  const сейчас = Date.now();
  const лежит = холодильник.get(имя);
  if (лежит && сейчас - лежит.когда < срокМс) return лежит.что;
  let что;
  try {
    что = await добыть();
  } catch (ошибка) {
    // Ни одна поломка добычи не должна ронять страницу целиком:
    // лучше показать старое значение и честную пометку, чем пустой экран.
    if (лежит) return лежит.что;
    throw ошибка;
  }
  холодильник.set(имя, { когда: сейчас, что: что });
  return что;
}

