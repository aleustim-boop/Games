/** Вытаскиваем из разметки номера версий: game.js?v=47 → {game.js: 47}. */
function номераВерсий(html) {
  const найденные = {};
  const образец = /(?:src|href)="([^"?]+)\?v=(\d+)"/g;
  let кусок;
  while ((кусок = образец.exec(html)) !== null) {
    const имя = кусок[1].split('/').pop();
    найденные[имя] = Number(кусок[2]);
  }
  return найденные;
}

function скачатьСтраницу(адрес, срокМс) {
  return new Promise(function (готово, беда) {
    const запрос = https.get(адрес, { timeout: срокМс }, function (ответ) {
      if (ответ.statusCode !== 200) {
        ответ.resume();
        беда(new Error('сайт ответил ' + ответ.statusCode));
        return;
      }
      let тело = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (кусок) { тело += кусок; });
      ответ.on('end', function () { готово(тело); });
    });
    запрос.on('timeout', function () { запрос.destroy(new Error('сайт молчит')); });
    запрос.on('error', беда);
  });
}

/** Сверяем версии на сайте с местным index.html. Расхождение = «не опубликовано». */
async function сверкаССайтом() {
  let местные = {};
  try {
    местные = номераВерсий(fs.readFileSync(path.join(КОРЕНЬ, 'index.html'), 'utf8'));
  } catch (ошибка) {
    return { доступен: false, беда: 'местный index.html не читается', расхождения: [], версии: [] };
  }

  let наСайте;
  try {
    наСайте = номераВерсий(await скачатьСтраницу(АДРЕС_САЙТА, 9000));
  } catch (ошибка) {
    return { доступен: false, беда: 'сайт не ответил: ' + ошибка.message, расхождения: [], версии: [] };
  }

  const версии = [];
  const расхождения = [];
  for (const имя of Object.keys(местные)) {
    const тут = местные[имя];
    const там = Object.prototype.hasOwnProperty.call(наСайте, имя) ? наСайте[имя] : null;
    версии.push({ имя: имя, тут: тут, там: там });
    if (там === null || там !== тут) расхождения.push({ имя: имя, тут: тут, там: там });
  }
  return { доступен: true, беда: null, версии: версии, расхождения: расхождения };
}

