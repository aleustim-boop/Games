/** Выполняем короткую команду git и возвращаем её вывод текстом. */
function спроситьGit(доводы) {
  const итог = spawnSync('git', доводы, { cwd: КОРЕНЬ, timeout: 8000, maxBuffer: 4 * 1024 * 1024, windowsHide: true });
  if (итог.error || итог.status !== 0) return null;
  // Сообщения коммитов лежат в UTF-8, поэтому читаем байты и разбираем сами.
  return итог.stdout.toString('utf8');
}

/** Один и тот же день по местным часам? */
function тотЖеДень(а, б) {
  return а.getFullYear() === б.getFullYear()
    && а.getMonth() === б.getMonth()
    && а.getDate() === б.getDate();
}

function часыМинуты(дата) {
  const ч = String(дата.getHours()).padStart(2, '0');
  const м = String(дата.getMinutes()).padStart(2, '0');
  return ч + ':' + м;
}

const МЕСЯЦЫ_РОД = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
  'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];

function деньСловами(дата) {
  return дата.getDate() + ' ' + МЕСЯЦЫ_РОД[дата.getMonth()];
}

/**
 * Записи публикаций.
 * Отдельно — то, что закоммичено, но ещё не отправлено на сайт: коммит
 * публикацией не является, игроки видят только отправленное.
 */
function собратьПубликации() {
  const текст = спроситьGit(['log', '-n', '250', '--pretty=format:%h\u0001%aI\u0001%s']);
  if (текст === null) {
    return { есть: false, сегодня: [], прошлыеДни: [], ждутОтправки: [], всего: 0 };
  }

  const записи = [];
  for (const строка of текст.split('\n')) {
    const части = строка.split('\u0001');
    if (части.length < 3) continue;
    const дата = new Date(части[1]);
    if (isNaN(дата.getTime())) continue;
    записи.push({ ключ: части[0], дата: дата, что: части[2] });
  }

  // Что уже отправлено наружу. Метка origin/main обновляется при отправке
  // с этого же компьютера, поэтому ей можно верить.
  const отправленные = new Set();
  const выложено = спроситьGit(['rev-list', '-n', '250', 'origin/main']);
  if (выложено !== null) {
    for (const строка of выложено.split('\n')) {
      const ключ = строка.trim();
      if (ключ) отправленные.add(ключ.slice(0, 7));
    }
  }
  const сверкаВозможна = выложено !== null;

  const сейчас = new Date();
  const сегодня = [];
  const ждутОтправки = [];
  const поДням = new Map();

  for (const запись of записи) {
    запись.выложено = сверкаВозможна ? отправленные.has(запись.ключ) : null;
    if (запись.выложено === false) ждутОтправки.push(запись);

    if (тотЖеДень(запись.дата, сейчас)) {
      сегодня.push(запись);
    } else {
      const ключДня = запись.дата.getFullYear() + '-' + запись.дата.getMonth() + '-' + запись.дата.getDate();
      if (!поДням.has(ключДня)) поДням.set(ключДня, { день: деньСловами(запись.дата), число: 0, примеры: [] });
      const день = поДням.get(ключДня);
      день.число += 1;
      if (день.примеры.length < 3) день.примеры.push(запись.что);
    }
  }

  return {
    есть: true,
    сверкаВозможна: сверкаВозможна,
    сегодня: сегодня,
    прошлыеДни: Array.from(поДням.values()).slice(0, 6),
    ждутОтправки: ждутОтправки,
    всего: записи.length
  };
}

/* ===========================================================================
   2. ЧТО В РАБОТЕ И В ОЧЕРЕДИ — разбор ЗАДАЧИ.md

   Файл ведёт штаб руками, значит разметка иногда будет не идеальной.
   Правило разбора: ничего не требовать и ни на чём не падать. Не понял
   строку — пропустил, не понял раздел — вернул пустой список и сказал об этом.
=========================================================================== */

const УРОВНИ = ['горит', 'скоро', 'потом', 'задел'];

/** Убираем разметку, чтобы в ячейке остался человеческий текст. */
function очиститьЯчейку(текст) {
  return String(текст)
    .replace(/\*\*/g, '')
    .replace(/`/g, '')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Разбиваем строку таблицы на ячейки. Не таблица — вернём null. */
function ячейкиСтроки(строка) {
  const обрезанная = строка.trim();
  if (!обрезанная.startsWith('|')) return null;
  const части = обрезанная.replace(/^\|/, '').replace(/\|\s*$/, '').split('|');
  return части.map(очиститьЯчейку);
}

/** Строка-разделитель вида |---|---| — её пропускаем. */
function этоРазделитель(ячейки) {
  return ячейки.every(function (я) { return /^:?-{2,}:?$/.test(я) || я === ''; });
}

/** Ищем уровень важности в любой ячейке строки. */
function уровеньВажности(ячейки) {
  for (const ячейка of ячейки) {
    const низ = ячейка.toLowerCase();
    for (const уровень of УРОВНИ) {
      if (низ === уровень) return уровень;
    }
  }
  return null;
}

/** Достаём оценку времени, если штаб её написал: «≈ 40 мин», «~2 часа». */
function оценкаВремени(текст) {
  const найдено = /[≈~]\s*\d+[.,]?\d*\s*(мин|минут\w*|час\w*|дн\w*)/i.exec(текст);
  return найдено ? найдено[0].replace(/\s+/g, ' ') : null;
}

const МЕСЯЦЫ_ПРЕФИКСЫ = ['янв', 'фев', 'мар', 'апр', 'ма', 'июн', 'июл', 'авг', 'сен', 'окт', 'ноя', 'дек'];

/** «7 сентября, 17:45» → настоящая дата. Не разобрали — вернём null. */
function разобратьКогда(текст) {
  const найдено = /(\d{1,2})\s+([а-яё]+)(?:\s+(\d{4}))?[, ]+\s*(\d{1,2}):(\d{2})/i.exec(текст);
  if (!найдено) return null;
  const месяцТекст = найдено[2].toLowerCase();
  let месяц = -1;
  for (let i = 0; i < МЕСЯЦЫ_ПРЕФИКСЫ.length; i++) {
    if (месяцТекст.startsWith(МЕСЯЦЫ_ПРЕФИКСЫ[i])) { месяц = i; break; }
  }
  if (месяц < 0) return null;
  const год = найдено[3] ? Number(найдено[3]) : new Date().getFullYear();
  const дата = new Date(год, месяц, Number(найдено[1]), Number(найдено[4]), Number(найдено[5]));
  return isNaN(дата.getTime()) ? null : дата;
}

/** Сколько времени задача уже идёт — по-человечески. */
function сколькоИдёт(начато) {
  if (!начато) return null;
  const минут = Math.round((Date.now() - начато.getTime()) / 60000);
  if (минут < 0) return null;
  if (минут < 60) return минут + ' мин';
  const часов = Math.floor(минут / 60);
  const остаток = минут % 60;
  if (часов < 24) return остаток ? часов + ' ч ' + остаток + ' мин' : часов + ' ч';
  return Math.floor(часов / 24) + ' дн';
}

/** Находим раздел по слову в заголовке и отдаём строки до следующего заголовка. */
function строкиРаздела(всеСтроки, словаЗаголовка) {
  let начало = -1;
  for (let i = 0; i < всеСтроки.length; i++) {
    const строка = всеСтроки[i];
    if (!/^#{2,3}\s/.test(строка)) continue;
    const низ = строка.toLowerCase();
    if (словаЗаголовка.some(function (слово) { return низ.includes(слово); })) { начало = i + 1; break; }
  }
  if (начало < 0) return [];
  const собранные = [];
  for (let i = начало; i < всеСтроки.length; i++) {
    if (/^#{1,3}\s/.test(всеСтроки[i])) break;
    собранные.push(всеСтроки[i]);
  }
  return собранные;
}

/** Строки таблицы раздела: без заголовка таблицы и без разделителей. */
function задачиРаздела(строки) {
  const задачи = [];
  let заголовокПропущен = false;
  for (const строка of строки) {
    const ячейки = ячейкиСтроки(строка);
    if (!ячейки || ячейки.length < 2) continue;
    if (этоРазделитель(ячейки)) { заголовокПропущен = true; continue; }
    // Первая строка таблицы — её шапка («Что | Важность | ...»), она нам не нужна.
    if (!заголовокПропущен) continue;
    if (!ячейки[0]) continue;
    задачи.push(ячейки);
  }
  return задачи;
}

/**
 * Разбор самого текста — отдельно от чтения с диска, чтобы разбор можно
 * было проверить на нарочно кривой разметке, не трогая настоящий файл.
 */
function разобратьТекстЗадач(текст) {
  const итог = {
    прочитано: true,
    вРаботе: [],
    очередь: [],
    вопросы: [],
    готово: [],
    пропущено: 0,
    правился: null,
    беда: null
  };

  const строки = String(текст).split(/\r?\n/);

  // В работе: Что | Важность | Кто делает | Начато
  for (const ячейки of задачиРаздела(строкиРаздела(строки, ['в работе']))) {
    const начато = разобратьКогда(ячейки[3] || '');
    итог.вРаботе.push({
      что: ячейки[0],
      уровень: уровеньВажности(ячейки) || 'скоро',
      кто: ячейки[2] || '',
      начатоТекст: ячейки[3] || '',
      идёт: сколькоИдёт(начато),
      оценка: оценкаВремени(ячейки.join(' '))
    });
  }

  // Очередь: Что | Важность | Заметка штаба
  for (const ячейки of задачиРаздела(строкиРаздела(строки, ['очеред']))) {
    // Уровень не написан или написан не тем словом — не беда, считаем «потом».
    const уровень = уровеньВажности(ячейки);
    if (!уровень) итог.пропущено += 1;

    // Подсказку «проверьте, не сделано ли» программа списки.js пишет прямо
    // в заметку. Отделяем её, чтобы на странице она встала заметно, а не
    // потерялась в конце длинной строки.
    let заметка = ячейки[2] || '';
    let подсказка = null;
    const разрыв = заметка.indexOf('⚠️');
    if (разрыв >= 0) {
      подсказка = заметка.slice(разрыв + 2).trim();
      заметка = заметка.slice(0, разрыв).trim();
    }

    итог.очередь.push({
      что: ячейки[0],
      уровень: уровень || 'потом',
      заметка: заметка,
      подсказка: подсказка,
      оценка: оценкаВремени(ячейки.join(' '))
    });
  }

  // Ждём слова владельца: О чём | Вопрос | Почему спрашиваем.
  // Это не наши задачи, и складывать их в очередь нельзя: владелец видел
  // «девять задач висят», а три из них были вопросами к нему самому.
  for (const ячейки of задачиРаздела(строкиРаздела(строки, ['ждём слова', 'ждем слова']))) {
    итог.вопросы.push({
      что: ячейки[0],
      вопрос: ячейки[1] || '',
      заметка: ячейки[2] || ''
    });
  }

  // Готово: Что | Когда
  for (const ячейки of задачиРаздела(строкиРаздела(строки, ['готово']))) {
    итог.готово.push({ что: ячейки[0], когда: ячейки[1] || '' });
  }

  if (!итог.вРаботе.length && !итог.очередь.length) {
    итог.беда = 'в ЗАДАЧИ.md не нашлось ни одной таблицы с задачами — проверьте разметку';
  }

  return итог;
}

/** Читаем ЗАДАЧИ.md с диска и отдаём разобранное. Не прочитали — говорим прямо. */
function разобратьЗадачи() {
  const файл = path.join(КОРЕНЬ, 'ЗАДАЧИ.md');

  let текст;
  try {
    текст = fs.readFileSync(файл, 'utf8');
  } catch (ошибка) {
    return {
      прочитано: false, вРаботе: [], очередь: [], вопросы: [], готово: [],
      пропущено: 0, правился: null,
      беда: 'файл ЗАДАЧИ.md не читается — списки показать нечем'
    };
  }

  let итог;
  try {
    итог = разобратьТекстЗадач(текст);
  } catch (ошибка) {
    // Разбор не должен ронять дашборд ни при какой разметке.
    return {
      прочитано: true, вРаботе: [], очередь: [], вопросы: [], готово: [],
      пропущено: 0, правился: null,
      беда: 'разметку ЗАДАЧИ.md разобрать не вышло: ' + ошибка.message
    };
  }

  try {
    итог.правился = fs.statSync(файл).mtime;
  } catch (ошибка) { /* время правки — приятная мелочь, без неё живём */ }

  return итог;
}

