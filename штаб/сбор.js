/** Короткий запрос к своей же машине. Молчит дольше срока — считаем, что стоит. */
function постучаться(адрес, срокМс) {
  return new Promise(function (готово) {
    const запрос = http.get(адрес, { timeout: срокМс }, function (ответ) {
      let тело = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (кусок) { if (тело.length < 4000) тело += кусок; });
      ответ.on('end', function () { готово({ жива: ответ.statusCode < 500, код: ответ.statusCode, тело: тело }); });
    });
    запрос.on('timeout', function () { запрос.destroy(); });
    запрос.on('error', function () { готово({ жива: false, код: 0, тело: '' }); });
  });
}

/**
 * Список запущенных программ — чтобы увидеть бота и туннель.
 * Читаем только имя и командную строку, ничего не запускаем и не гасим.
 * Кириллица в этом выводе портится кодировкой консоли, поэтому ищем
 * по латинским кускам пути: 'bot/' и 'cloudflared'.
 */
function запущенныеПрограммы() {
  const запрос = "Get-CimInstance Win32_Process -Filter \"Name='node.exe' or Name='cloudflared.exe'\" | ForEach-Object { $_.Name + '|' + $_.CommandLine }";
  // windowsHide обязателен: у дашборда нет своей консоли, и без него Windows
  // открывает под каждый запуск новое окно — оно мигает на экране каждые 15 секунд.
  const итог = spawnSync('powershell', ['-NoProfile', '-NonInteractive', '-Command', запрос], { timeout: 9000, maxBuffer: 2 * 1024 * 1024, windowsHide: true });
  if (итог.error || !итог.stdout) return null;
  return итог.stdout.toString('latin1').toLowerCase();
}

async function состояниеСлужб() {
  const комнаты = await постучаться('http://127.0.0.1:8790/', 2500);
  let числоКомнат = null;
  if (комнаты.жива) {
    try {
      const разобрано = JSON.parse(комнаты.тело);
      if (разобрано && typeof разобрано['комнат'] === 'number') числоКомнат = разобрано['комнат'];
    } catch (ошибка) { /* ответил не тем — всё равно жив */ }
  }

  const страница = await постучаться('http://127.0.0.1:8080/index.html', 2500);
  const программы = запущенныеПрограммы();

  return {
    комнаты: { жива: комнаты.жива, подпись: числоКомнат === null ? ':8790' : ':8790 · комнат ' + числоКомнат },
    страницаИгры: { жива: страница.жива, подпись: ':8080' },
    бот: {
      жива: программы === null ? null : (программы.includes('bot/') || программы.includes('bot\\')),
      подпись: '@BoardingGames_bot'
    },
    туннель: {
      жива: программы === null ? null : программы.includes('cloudflared'),
      подпись: 'cloudflare'
    }
  };
}

