/** Заголовки записей: ключ, время и текст. Не вышло — честный null. */
function записиGit(сколько) {
  const итог = spawnSync('git', ['log', '-n', String(сколько || 300), '--pretty=format:%h%aI%s'],
    { cwd: КОРЕНЬ, timeout: 8000, maxBuffer: 4 * 1024 * 1024, windowsHide: true });
  if (итог.error || итог.status !== 0) return null;

  const записи = [];
  for (const строка of итог.stdout.toString('utf8').split('\n')) {
    const части = строка.split('');
    if (части.length < 3) continue;
    const дата = new Date(части[1]);
    if (isNaN(дата.getTime())) continue;
    записи.push({ ключ: части[0], дата: дата, что: части[2] });
  }
  return записи;
}

/* ---------------------------------------------------------------------------
   Способ 1: примета в коде
--------------------------------------------------------------------------- */

/**
 * Что лежит в ОПУБЛИКОВАННОМ файле, а не на диске.
 *
 * Отвечает текстом файла из origin/main, либо null — если такого файла
 * там нет или спросить git не вышло. Пустой файл отдаётся пустой строкой,
 * и это не то же самое, что null: файл есть, просто он пуст.
 */
function опубликованныйФайл(имя) {
  const итог = spawnSync('git', ['show', 'origin/main:' + имя],
    { cwd: КОРЕНЬ, timeout: 8000, maxBuffer: 8 * 1024 * 1024, windowsHide: true });
  if (итог.error || итог.status !== 0) return null;
  return итог.stdout.toString('utf8');
}

/** Знает ли этот компьютер, что такое origin/main. */
function публикацияВидна() {
  const итог = spawnSync('git', ['rev-parse', '--verify', 'origin/main'],
    { cwd: КОРЕНЬ, timeout: 8000, windowsHide: true });
  return !итог.error && итог.status === 0;
}

/** Когда этот файл в последний раз менялся в опубликованном. */
function когдаОпубликован(имя) {
  const итог = spawnSync('git', ['log', '-1', '--format=%aI', 'origin/main', '--', имя],
    { cwd: КОРЕНЬ, timeout: 8000, windowsHide: true });
  if (итог.error || итог.status !== 0) return null;
  const строка = итог.stdout.toString('utf8').trim();
  if (!строка) return null;
  const дата = new Date(строка);
  return isNaN(дата.getTime()) ? null : дата;
}

/**
 * Есть ли в ОПУБЛИКОВАННОМ коде обещанный след.
 *
 * ПОЧЕМУ НЕ С ДИСКА. Раньше эта примета читала файл в рабочем дереве —
 * и записывала дело в «Готово», как только исполнитель заводил у себя
 * нужную строку. Работа при этом не была ни сдана, ни проверена, ни
 * опубликована: игрок по-прежнему не мог попасть в нарды, а в списке
 * значилось «готово». Владелец дважды ловил нас на такой неправде.
 *
 * Готово — это то, что доехало до игроков. Значит смотреть надо в то же
 * место, откуда игра берётся у них: в опубликованное (origin/main).
 *
 * Публикации не видно вовсе (нет сети, чужой компьютер) — тогда примета
 * молчит и ничего не вычёркивает. Молчание здесь дешевле выдумки.
 */
function следВКоде(примета) {
  if (!примета || !примета.файл) return null;

  if (!публикацияВидна()) {
    return { нашлось: false, чем: 'опубликованного не видно (нет origin/main) — сверять не с чем' };
  }

  const текст = опубликованныйФайл(примета.файл);
  if (текст === null) {
    return { нашлось: false, чем: 'файла ' + примета.файл + ' нет в опубликованном' };
  }

  /* Оба поля могут быть заданы разом — тогда дело сделано, только когда
     сошлись ОБА условия. Раньше при таком совпадении можно было бы молча
     взять первое попавшееся поле — это менее честно, поэтому проверяем
     каждое заданное поле и складываем пояснения. */
  const пояснения = [];
  let всёСошлось = true;

  if (примета.есть) {
    if (текст.indexOf(примета.есть) === -1) {
      всёСошлось = false;
      пояснения.push(
        'в опубликованном ' + примета.файл + ' нет «' + примета.есть + '»' +
        (естьНаДиске(примета, 'есть') ? ' (на диске есть — работа не опубликована)' : '')
      );
    } else {
      пояснения.push('в опубликованном ' + примета.файл + ' есть «' + примета.есть + '»');
    }
  }

  if (примета.нету) {
    if (текст.indexOf(примета.нету) !== -1) {
      всёСошлось = false;
      пояснения.push(
        'в опубликованном ' + примета.файл + ' всё ещё есть «' + примета.нету + '»' +
        (естьНаДиске(примета, 'нету') ? ' (на диске уже нет — работа не опубликована)' : '')
      );
    } else {
      пояснения.push('в опубликованном ' + примета.файл + ' больше нет «' + примета.нету + '»');
    }
  }

  if (!примета.есть && !примета.нету) {
    return { нашлось: true, чем: 'файл ' + примета.файл + ' опубликован' };
  }

  return { нашлось: всёСошлось, чем: пояснения.join('; ') };
}

/** Совпадает ли обещание приметы с тем, что лежит на диске СЕЙЧАС. Нужно
    ровно для одного — сказать штабу «сделано, но не опубликовано», а не
    сухое «нет». Второй параметр говорит, какое поле приметы проверяем:
    для «есть» ищем строку на диске, для «нету» — наоборот, убеждаемся,
    что строки на диске уже нет (значит работа сделана локально). */
function естьНаДиске(примета, поле) {
  try {
    const текст = fs.readFileSync(path.join(КОРЕНЬ, примета.файл), 'utf8');
    if (поле === 'нету') {
      return примета.нету ? текст.indexOf(примета.нету) === -1 : true;
    }
    return примета.есть ? текст.indexOf(примета.есть) !== -1 : true;
  } catch (ошибка) {
    return false;
  }
}

