/* Сверка очереди с тем, что уже сделано, — без участия памяти штаба.

   Зачем. Владелец спросил: «почему в дашборде у меня постоянно висит
   9 задач в очереди?» Пять из девяти были давно сделаны и опубликованы.
   Раздел «В работе» к тому времени уже вела программа, а очередь осталась
   на памяти — память и подвела, ровно как раньше со временем.

   Тут три способа узнать, что пункт сделан, и они нарочно разной силы.
   Порядок важен: сначала пробуем самый надёжный.

   1. ПРИМЕТА В КОДЕ — самая крепкая. Штаб пишет у пункта, по какому следу
      в коде видно, что дело сделано: появился файл или в файле появилась
      строка. Это добывается с диска, не зависит ни от чьей памяти, ни от
      того, какими словами написан коммит.

          "сделано": { "файл": "js/рейтинг-экран.js" }
          "сделано": { "файл": "js/game.js", "есть": "HapticFeedback" }

   2. ПРИМЕТА В КОММИТЕ — послабее. Штаб заранее говорит, какие слова
      появятся в заголовке записи git. Все слова должны встретиться в одном
      заголовке, иначе не считается.

          "сделано": { "слова": ["рейтинг"] }

   3. ПОХОЖЕСТЬ — самая слабая, и она НИЧЕГО НЕ ВЫЧЁРКИВАЕТ. Программа сама
      берёт значимые слова из названия пункта и ищет их в заголовках записей
      за последние дни. Нашла — ставит рядом пометку «проверьте, не сделано
      ли». Решает человек, но забыть ему уже не дадут.

   Почему третий способ нельзя пускать дальше пометки — проверено на живых
   записях этого проекта: из пяти сделанных дел он опознал три. «Рейтинг»,
   «шрифт» и «вибрация» нашлись, а «брызги от броска» и «анимация» — нет,
   потому что коммиты написаны образно: «карты полетели», «брошенное пачкает
   стол». Ни одного общего слова с названием пункта. */

'use strict';

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const КОРЕНЬ = path.resolve(path.join(__dirname, '..'));

/* Слова, которые встречаются в каждом втором заголовке и потому ничего не
   значат при поиске похожести. Без этого списка «игра» и «карты» связали бы
   любой пункт с любым коммитом. */
const ПУСТЫЕ_СЛОВА = new Set([
  'что', 'как', 'для', 'при', 'без', 'над', 'под', 'про', 'это', 'его', 'ещё',
  'уже', 'все', 'всё', 'или', 'если', 'чтобы', 'когда', 'также', 'ещё',
  'игра', 'игре', 'игры', 'игру', 'игрок', 'игрока', 'игроков', 'игроку',
  'карта', 'карты', 'карт', 'картам', 'экран', 'экране', 'штаб', 'штаба',
  'сделать', 'сделан', 'новый', 'новая', 'новое', 'свой', 'своя', 'своё',
  'один', 'два', 'три', 'вместо', 'после', 'перед', 'через', 'стал', 'стала',
  'стало', 'стали', 'больше', 'меньше', 'можно', 'нужно', 'надо'
]);

/* ---------------------------------------------------------------------------
   Записи git
--------------------------------------------------------------------------- */

/** Заголовки записей: ключ, время и текст. Не вышло — честный null. */
function записиGit(сколько) {
  const итог = spawnSync('git', ['log', '-n', String(сколько || 300), '--pretty=format:%h%aI%s'],
    { cwd: КОРЕНЬ, timeout: 8000, maxBuffer: 4 * 1024 * 1024 });
  if (итог.error || итог.status !== 0) return null;

  const записи = [];
  for (const строка of итог.stdout.toString('utf8').split('\n')) {
    const части = строка.split('');
    if (части.length < 3) continue;
    const дата = new Date(части[1]);
    if (isNaN(дата.getTime())) continue;
    записи.push({ ключ: части[0], дата: дата, что: части[2] });
  }
  return записи;
}

/* ---------------------------------------------------------------------------
   Способ 1: примета в коде
--------------------------------------------------------------------------- */

/**
 * Есть ли в коде обещанный след.
 * Читаем только названный файл и только чтобы поискать в нём строку.
 */
function следВКоде(примета) {
  if (!примета || !примета.файл) return null;
  const путь = path.join(КОРЕНЬ, примета.файл);

  let есть = fs.existsSync(путь);
  if (!есть) return { нашлось: false, чем: 'файла ' + примета.файл + ' нет' };

  if (примета.есть) {
    let текст = '';
    try {
      текст = fs.readFileSync(путь, 'utf8');
    } catch (ошибка) {
      return { нашлось: false, чем: примета.файл + ' не читается' };
    }
    if (текст.indexOf(примета.есть) === -1) {
      return { нашлось: false, чем: 'в ' + примета.файл + ' нет «' + примета.есть + '»' };
    }
    return { нашлось: true, чем: 'в ' + примета.файл + ' есть «' + примета.есть + '»' };
  }

  return { нашлось: true, чем: 'файл ' + примета.файл + ' появился' };
}

/* ---------------------------------------------------------------------------
   Способ 2: примета в заголовке записи git
--------------------------------------------------------------------------- */

/** Все заданные слова встретились в одном заголовке — значит сделано. */
function следВЗаписях(слова, записи) {
  if (!Array.isArray(слова) || !слова.length || !записи) return null;
  const нижние = слова.map(function (с) { return String(с).toLowerCase(); });

  for (const запись of записи) {
    const текст = запись.что.toLowerCase();
    let всеЕсть = true;
    for (const слово of нижние) {
      if (текст.indexOf(слово) === -1) { всеЕсть = false; break; }
    }
    if (всеЕсть) return { нашлось: true, запись: запись, чем: 'в записи «' + запись.что + '»' };
  }
  return { нашлось: false, чем: 'в записях git слов ' + слова.join(' + ') + ' не встретилось' };
}

/* ---------------------------------------------------------------------------
   Способ 3: похожесть — только подсказка, не вычёркивание
--------------------------------------------------------------------------- */

/** Значимые слова названия: длиннее четырёх букв и не из пустых. */
function значимыеСлова(текст) {
  const слова = String(текст).toLowerCase().replace(/[^а-яёa-z0-9 ]/gi, ' ').split(/\s+/);
  const итог = [];
  for (const слово of слова) {
    if (слово.length < 5) continue;
    if (ПУСТЫЕ_СЛОВА.has(слово)) continue;
    // Берём корень: окончания в русском гуляют, «вибрация» и «вибрацию» —
    // одно и то же слово, а сравниваем мы кусками.
    итог.push(слово.slice(0, слово.length - 2));
  }
  return безПовторов(итог);
}

function безПовторов(список) {
  const видели = new Set();
  const итог = [];
  for (const слово of список) {
    if (видели.has(слово)) continue;
    видели.add(слово);
    итог.push(слово);
  }
  return итог;
}

/**
 * Ищем записи, похожие на название пункта. Возвращаем самую свежую.
 * Порог — два общих корня, либо один, но длинный (от шести букв):
 * при одном коротком совпадении подсказка превращается в шум.
 */
function похожаяЗапись(название, записи, зачтоДней) {
  if (!записи || !записи.length) return null;
  const корни = значимыеСлова(название);
  if (!корни.length) return null;

  const рубеж = Date.now() - (зачтоДней || 7) * 24 * 60 * 60 * 1000;
  let лучшая = null;

  for (const запись of записи) {
    if (запись.дата.getTime() < рубеж) continue;
    const текст = запись.что.toLowerCase();
    const совпали = корни.filter(function (к) { return текст.indexOf(к) !== -1; });
    const весомо = совпали.length >= 2 || (совпали.length === 1 && совпали[0].length >= 5);
    if (!весомо) continue;
    if (!лучшая || запись.дата > лучшая.запись.дата) лучшая = { запись: запись, совпали: совпали };
  }
  return лучшая;
}

/* ---------------------------------------------------------------------------
   Всё вместе: что стало с пунктом очереди
--------------------------------------------------------------------------- */

/**
 * Разбираем один пункт очереди.
 * Возвращаем: сделан ли (и по какой примете), либо подсказку «проверьте».
 */
function разобратьПункт(пункт, записи) {
  const итог = { что: пункт.что, сделан: false, чем: null, когда: null, подсказка: null };

  const примета = пункт.сделано || null;

  // Первый пояс — след в коде.
  if (примета && примета.файл) {
    const код = следВКоде(примета);
    if (код && код.нашлось) {
      итог.сделан = true;
      итог.чем = код.чем;
      // Времени у следа в коде нет, поэтому берём его у записи git, если
      // штаб заодно назвал слова. Не назвал — время оставим пустым, а не
      // выдумаем.
      const поЗаписи = следВЗаписях(примета.слова, записи);
      if (поЗаписи && поЗаписи.нашлось) итог.когда = поЗаписи.запись.дата;
      return итог;
    }
  }

  // Второй пояс — заранее объявленные слова в заголовке записи.
  if (примета && примета.слова) {
    const поЗаписи = следВЗаписях(примета.слова, записи);
    if (поЗаписи && поЗаписи.нашлось) {
      итог.сделан = true;
      итог.чем = поЗаписи.чем;
      итог.когда = поЗаписи.запись.дата;
      return итог;
    }
  }

  // Третий пояс — только подсказка человеку.
  const похожа = похожаяЗапись(пункт.что, записи, 7);
  if (похожа) {
    итог.подсказка = {
      что: похожа.запись.что,
      когда: похожа.запись.дата,
      совпали: похожа.совпали
    };
  }
  return итог;
}

/**
 * Сторож от забывчивости.
 * Ловит ту самую дыру, из-за которой владелец увидел девять пунктов: за день
 * сделано много записей, а очередь не уменьшилась ни на один пункт.
 */
function очередьНеДвигалась(записи, времяПравкиОчереди) {
  if (!записи || !времяПравкиОчереди) return null;

  const сутки = Date.now() - 24 * 60 * 60 * 1000;
  const заСутки = записи.filter(function (з) { return з.дата.getTime() > сутки; }).length;
  if (заСутки < 5) return null; // работы было мало — молчим, повода нет

  const часовБезПравки = Math.floor((Date.now() - времяПравкиОчереди.getTime()) / 3600000);
  if (часовБезПравки < 3) return null;

  return { записей: заСутки, часов: часовБезПравки };
}

module.exports = {
  записиGit: записиGit,
  разобратьПункт: разобратьПункт,
  следВКоде: следВКоде,
  следВЗаписях: следВЗаписях,
  похожаяЗапись: похожаяЗапись,
  значимыеСлова: значимыеСлова,
  очередьНеДвигалась: очередьНеДвигалась
};
