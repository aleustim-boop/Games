const ПРОГРАММЫ_ПЕРЕСБОРКИ = ['списки.js', 'в-работе.js', 'важное.js'];
const ШАГ_ПЕРЕСБОРКИ_МС = страница.ПЕРЕСБОРКА_МИН * 60 * 1000;
// Одна программа дольше минуты — значит зависла; снимаем, чтобы не копились.
const СРОК_ПРОГРАММЫ_МС = 60 * 1000;

/* Состояние пересборки. Время последней — из часов машины в ту минуту,
   когда пересборка закончилась, и никак иначе. */
const пересборка = { идёт: false, последняя: null, шаги: [], шагМин: страница.ПЕРЕСБОРКА_МИН };

/** Самая говорящая строка из вывода программы: ошибка, если она есть. */
function главнаяСтрока(вывод, ошибки, прошёл) {
  const строки = (String(вывод || '') + '\n' + String(ошибки || ''))
    .split(/\r?\n/)
    .map(function (с) { return с.trim(); })
    .filter(Boolean);
  if (!строки.length) return '';
  if (прошёл) return строки[0].slice(0, 200);
  const ошибка = строки.find(function (с) { return /^[A-Za-z]*Error:/.test(с); });
  return (ошибка || строки.slice(0, 2).join(' ')).slice(0, 200);
}

/** Запускаем одну программу штаба и ждём её конца. Не падаем ни при каком исходе. */
function запуститьПрограмму(имя) {
  return new Promise(function (готово) {
    execFile(process.execPath, [path.join(__dirname, имя)], {
      cwd: path.join(__dirname, '..'),
      timeout: СРОК_ПРОГРАММЫ_МС,
      windowsHide: true,
      maxBuffer: 1024 * 1024
    }, function (ошибка, вывод, ошибки) {
      const прошёл = !ошибка;
      готово({
        имя: имя,
        прошёл: прошёл,
        строка: прошёл ? главнаяСтрока(вывод, '', true)
          : (главнаяСтрока(вывод, ошибки, false) || String(ошибка.message || ошибка).slice(0, 200))
      });
    });
  });
}

/** Три программы по очереди: они правят один файл, вместе им нельзя. */
async function пересобрать() {
  if (пересборка.идёт) return; // прошлая ещё не кончилась — не накладываем
  пересборка.идёт = true;
  const шаги = [];
  try {
    for (const имя of ПРОГРАММЫ_ПЕРЕСБОРКИ) шаги.push(await запуститьПрограмму(имя));
  } finally {
    пересборка.шаги = шаги;
    пересборка.последняя = new Date();
    пересборка.идёт = false;
  }
  const сбои = шаги.filter(function (ш) { return !ш.прошёл; });
  console.log('пересобрано ' + часыСловами()
    + (сбои.length ? ' — не прошли: ' + сбои.map(function (ш) { return ш.имя + ' (' + ш.строка + ')'; }).join('; ') : ''));
}

/**
 * Пересборка с перехватом. Беда внутри неё не должна ронять весь дашборд:
 * необработанный отказ обещания в нынешнем Node гасит процесс целиком,
 * и владелец терял бы страницу из-за одной сломанной программы. Беду
 * кладём в сбои пересборки — её увидит полоса «Пересборка списков не прошла».
 */
function пересобратьБезПадения() {
  пересобрать().catch(function (ошибка) {
    const слова = String(ошибка && ошибка.message ? ошибка.message : ошибка).slice(0, 200);
    console.error('пересборка упала: ' + слова);
    пересборка.шаги = [{ имя: 'пересборка', прошёл: false, строка: слова }];
    пересборка.последняя = new Date();
    пересборка.идёт = false;
  });
}

/* ---------------------------------------------------------------------------
   Письмо словами: POST /сказать

   Единственная дверь, которая читает тело запроса, а не только адрес.
   Тело — обычная HTML-форма (application/x-www-form-urlencoded), без
   своего JavaScript: браузер отправляет её сам.

   Предел на тело — с большим запасом на процентную кодировку: кириллица
   в urlencoded виде — три символа на байт, поэтому даже 4000 знаков текста
   разрастаются в разы. Предел нужен не для текста (тот режется ниже до
   ПРЕДЕЛ_ТЕКСТА_ЗНАКОВ), а чтобы кто-то не завалил сервер гигабайтным телом.
--------------------------------------------------------------------------- */

const ПРЕДЕЛ_ТЕЛА_БАЙТ = 200 * 1024;      // с запасом на percent-encoding кириллицы
const ПРЕДЕЛ_ТЕКСТА_ЗНАКОВ = 4000;

/** Принимаем письмо: читаем тело, проверяем поля, пишем в файл или отказываем словами. */
function принятьПисьмо(запрос, ответ) {
  const части = [];
  let набралБайт = 0;
  let слишкомДлинное = false;

  запрос.on('data', function (кусок) {
    набралБайт += кусок.length;
    if (набралБайт > ПРЕДЕЛ_ТЕЛА_БАЙТ) {
      слишкомДлинное = true;
      return; // дальше не копим — лишнее всё равно не понадобится
    }
    части.push(кусок);
  });

  запрос.on('error', function () {
    // Соединение оборвалось на середине — ответ уже никто не примет.
  });

  запрос.on('end', function () {
    if (слишкомДлинное) {
      отдать(ответ, 413, 'text/plain; charset=utf-8', 'сообщение слишком длинное, отправьте короче');
      return;
    }

    let поля;
    try {
      поля = new URLSearchParams(Buffer.concat(части).toString('utf8'));
    } catch (ошибка) {
      отдать(ответ, 400, 'text/plain; charset=utf-8', 'не удалось разобрать отправленное');
      return;
    }

    const ключЗаписи = String(поля.get('запись') || '').trim();
    const текст = String(поля.get('текст') || '').trim().slice(0, ПРЕДЕЛ_ТЕКСТА_ЗНАКОВ);

    let запись = null;
    if (ключЗаписи) {
      запись = важное.найтиЗапись(ключЗаписи);
      if (!запись) {
        отдать(ответ, 400, 'text/plain; charset=utf-8', 'нет такой записи «Важного» — письмо не сохранено');
        return;
      }
    }

    if (!текст) {
      отдать(ответ, 400, 'text/plain; charset=utf-8', 'текст пуст — писать нечего, письмо не сохранено');
      return;
    }

    записатьПисьмо(ключЗаписи, текст);
    отдать(ответ, 200, 'text/html; charset=utf-8', важное.страницаПисьмоЗаписано(запись));
  });
}

/* ---------------------------------------------------------------------------
   Очередь из браузера: /очередь-изменить, /очередь-выше, /очередь-ниже, /очередь-удалить, /очередь-добавить

   Владелец правит штаб/списки.json сам, без просьбы к разработчику лезть
   в json руками. Приём тот же, что у /сказать выше: обычная HTML-форма,
   без своего JavaScript, тело читаем тем же способом с тем же пределом байт.

   Индекс записи — просто позиция в массиве «очередь» на момент, когда
   страница рисовалась; форма несёт его скрытым полем. Между отрисовкой
   и отправкой формы список мог поменяться (открыты два окна, ответ владельца
   задержался) — тогда индекс может указывать не туда или вообще выйти за
   край массива. Проверяем это перед правкой и, если не сходится, ничего
   не трогаем и отвечаем понятным отказом, а не тем, что попало под руку.
--------------------------------------------------------------------------- */

const ФАЙЛ_СПИСКОВ_ОЧЕРЕДЬ = path.join(__dirname, 'списки.json');
const ВАЖНОСТИ_ОЧЕРЕДИ = ['горит', 'скоро', 'потом', 'задел'];
const ПРЕДЕЛ_ЗАДАЧИ_ЗНАКОВ = 300;

/** Читаем тело формы (application/x-www-form-urlencoded) тем же приёмом, что и /сказать. */
function прочитатьТелоФормы(запрос, готово) {
  const части = [];
  let набралБайт = 0;
  let слишкомДлинное = false;

  запрос.on('data', function (кусок) {
    набралБайт += кусок.length;
    if (набралБайт > ПРЕДЕЛ_ТЕЛА_БАЙТ) {
      слишкомДлинное = true;
      return;
    }
    части.push(кусок);
  });

  запрос.on('error', function () {
    // Соединение оборвалось на середине — отвечать уже некому.
  });

  запрос.on('end', function () {
    if (слишкомДлинное) {
      готово(null, 'сообщение слишком длинное, отправьте короче');
      return;
    }
    let поля;
    try {
      поля = new URLSearchParams(Buffer.concat(части).toString('utf8'));
    } catch (ошибка) {
      готово(null, 'не удалось разобрать отправленное');
      return;
    }
    готово(поля, null);
  });
}

/** Читаем штаб/списки.json целиком. Не читается или битый JSON — данные: null и текст беды. */
function прочитатьСпискиОчереди() {
  let сырое;
  try {
    сырое = fs.readFileSync(ФАЙЛ_СПИСКОВ_ОЧЕРЕДЬ, 'utf8');
  } catch (ошибка) {
    return { данные: null, беда: 'файл штаб/списки.json не читается' };
  }
  let данные;
  try {
    данные = JSON.parse(сырое);
  } catch (ошибка) {
    return { данные: null, беда: 'штаб/списки.json повреждён: ' + ошибка.message };
  }
  if (!Array.isArray(данные.очередь)) данные.очередь = [];
  return { данные: данные, беда: null };
}

/** Пишем штаб/списки.json тем же стилем отступов, каким его пишет штаб/списки.js. */
function записатьСпискиОчереди(данные) {
  fs.writeFileSync(ФАЙЛ_СПИСКОВ_ОЧЕРЕДЬ, JSON.stringify(данные, null, 2) + '\n', 'utf8');
}

/** Небольшая страница-отказ: правка не прошла, но ничего не сломано и не потеряно. */
function страницаОтказаОчереди(сообщение) {
  return '<!doctype html><meta charset="utf-8">'
    + '<title>Штаб — очередь</title>'
    + '<body style="font-family:system-ui;padding:24px;line-height:1.5">'
    + '<h1>Правка не прошла</h1>'
    + '<p>' + String(сообщение) + '</p>'
    + '<p><a href="/">‹ Назад на дашборд</a></p>'
    + '</body>';
}

/** Разбираем и проверяем индекс записи из формы. Не число или отрицательный — null. */
function индексИзФормы(поля) {
  const индекс = Number(поля.get('индекс'));
  return Number.isInteger(индекс) && индекс >= 0 ? индекс : null;
}

/** POST /очередь-изменить: меняем важность одной записи по её индексу в массиве. */
function обработатьОчередьИзменить(запрос, ответ) {
  прочитатьТелоФормы(запрос, function (поля, ошибкаЧтения) {
    if (!поля) {
      отдать(ответ, 400, 'text/html; charset=utf-8', страницаОтказаОчереди(ошибкаЧтения));
      return;
    }
    const индекс = индексИзФормы(поля);
    const важность = String(поля.get('важность') || '');
    if (индекс === null) {
      отдать(ответ, 400, 'text/html; charset=utf-8', страницаОтказаОчереди('в форме потерялся номер записи — откройте дашборд заново и попробуйте ещё раз.'));
      return;
    }
    if (ВАЖНОСТИ_ОЧЕРЕДИ.indexOf(важность) === -1) {
      отдать(ответ, 400, 'text/html; charset=utf-8', страницаОтказаОчереди('незнакомая важность — выберите одно из значений в списке.'));
      return;
    }
    const { данные, беда } = прочитатьСпискиОчереди();
    if (!данные) {
      отдать(ответ, 500, 'text/html; charset=utf-8', страницаОтказаОчереди(беда));
      return;
    }
    if (индекс >= данные.очередь.length) {
      отдать(ответ, 400, 'text/html; charset=utf-8', страницаОтказаОчереди('список успели поменять, пока вы правили, — эта запись сдвинулась. Откройте дашборд заново и попробуйте ещё раз.'));
      return;
    }
    данные.очередь[индекс].важность = важность;
    try {
      записатьСпискиОчереди(данные);
    } catch (ошибка) {
      отдать(ответ, 500, 'text/html; charset=utf-8', страницаОтказаОчереди('запись на диск не удалась: ' + ошибка.message));
      return;
    }
    пересобратьБезПадения();
    ответ.writeHead(302, { Location: '/' });
    ответ.end();
  });
}

/**
 * Общая часть для /очередь-выше и /очередь-ниже: меняем местами запись
 * по её индексу с соседней (сосед — индекс-1 для «выше», индекс+1 для
 * «ниже»). Порядок в массиве — это и есть приоритет владельца, поэтому
 * трогаем только позиции двух записей, важность и текст не меняем.
 */
function передвинутьЗаписьОчереди(запрос, ответ, сосед) {
  прочитатьТелоФормы(запрос, function (поля, ошибкаЧтения) {
    if (!поля) {
      отдать(ответ, 400, 'text/html; charset=utf-8', страницаОтказаОчереди(ошибкаЧтения));
      return;
    }
    const индекс = индексИзФормы(поля);
    if (индекс === null) {
      отдать(ответ, 400, 'text/html; charset=utf-8', страницаОтказаОчереди('в форме потерялся номер записи — откройте дашборд заново и попробуйте ещё раз.'));
      return;
    }
    const { данные, беда } = прочитатьСпискиОчереди();
    if (!данные) {
      отдать(ответ, 500, 'text/html; charset=utf-8', страницаОтказаОчереди(беда));
      return;
    }
    const соседИндекс = индекс + сосед;
    // Список могли успеть поменять между отрисовкой и отправкой формы, да
    // и верхнюю строку «выше», а нижнюю «ниже» двигать некуда — в обоих
    // случаях просто ничего не трогаем и отвечаем понятным отказом.
    if (индекс >= данные.очередь.length || соседИндекс < 0 || соседИндекс >= данные.очередь.length) {
      отдать(ответ, 400, 'text/html; charset=utf-8', страницаОтказаОчереди('список успели поменять, пока вы правили, — эта запись сдвинулась. Откройте дашборд заново и попробуйте ещё раз.'));
      return;
    }
    const временно = данные.очередь[индекс];
    данные.очередь[индекс] = данные.очередь[соседИндекс];
    данные.очередь[соседИндекс] = временно;
    try {
      записатьСпискиОчереди(данные);
    } catch (ошибка) {
      отдать(ответ, 500, 'text/html; charset=utf-8', страницаОтказаОчереди('запись на диск не удалась: ' + ошибка.message));
      return;
    }
    пересобратьБезПадения();
    ответ.writeHead(302, { Location: '/' });
    ответ.end();
  });
}

/** POST /очередь-выше: меняем запись местами с предыдущей — поднимаем её приоритет. */
function обработатьОчередьВыше(запрос, ответ) {
  передвинутьЗаписьОчереди(запрос, ответ, -1);
}

/** POST /очередь-ниже: меняем запись местами со следующей — опускаем её приоритет. */
function обработатьОчередьНиже(запрос, ответ) {
  передвинутьЗаписьОчереди(запрос, ответ, 1);
}

