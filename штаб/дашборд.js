/* Дашборд штаба: страница «что делается прямо сейчас», которую собирает
   программа, а не рука.

   Запуск:  node штаб/дашборд.js          (порт 8791)
            node штаб/дашборд.js 8799     (другой порт, если 8791 занят)
   Открыть: http://127.0.0.1:8791/

   Порты вокруг заняты: 8790 — сервер комнат, 8080 — страница игры,
   8765 — чужая программа. Поэтому 8791.

   ПРО БЕЗОПАСНОСТЬ — читать обязательно, если будете это править.
   Подход тот же, что в tests/локальный-сервер.js, и по той же причине:
   в папке проекта лежит bot/.env с настоящим токеном бота.

   1. Слушаем только 127.0.0.1 — свой компьютер. Без второго довода у listen
      сервер слушает все сетевые карты, и тогда любой человек в той же
      Wi-Fi-сети попадёт на эту страницу. Менять на 0.0.0.0 нельзя.
      Наружу страницу выводит туннель (cloudflared) — это осознанное решение
      штаба, и делается оно отдельно, не здесь.

   2. Файлы с диска этот сервер не отдаёт вовсе — ни одного. У него всего
      два адреса, и оба возвращают заранее собранную разметку. Значит
      попасть на bot/.env через него невозможно в принципе: нет такого пути,
      по которому имя файла из запроса дошло бы до диска.

   3. Ничего не выполняется по просьбе из браузера. Команды, которые сервер
      запускает (git, powershell для списка программ), записаны в коде
      постоянными строками и от запроса не зависят никак.

   4. Страница показывает состояние работы: названия задач, часы публикаций,
      огоньки служб. Ни путей к секретам, ни содержимого файлов на ней нет. */

'use strict';

const http = require('http');
const fs = require('fs');
const path = require('path');
const сбор = require('./сбор.js');
const страница = require('./страница.js');
const важное = require('./важное-страница.js');
const разборПути = require('./разбор-пути.js');

/* Что этот сервер пишет на диск — всего две вещи, и обе про владельца:
   какие записи он открывал и что он ответил кнопкой. Ни имя файла, ни
   содержимое из запроса не берутся: файлы постоянные, а из адреса
   достаётся только ключ, который сверяется со списком известных записей.
   Всё остальное на сервере по-прежнему только читает. */
const ФАЙЛ_ПРОЧИТАННОГО = важное.ФАЙЛ_ПРОЧИТАННОГО;
const ФАЙЛ_ОТВЕТОВ = важное.ФАЙЛ_ОТВЕТОВ;

const ПОРТ = Number(process.argv[2]) || 8791;
// Только свой компьютер. См. пояснение выше — менять нельзя.
const АДРЕС = '127.0.0.1';

function отдать(ответ, код, тип, тело) {
  ответ.writeHead(код, {
    'Content-Type': тип,
    // Дашборд обязан быть свежим: сохранённая копия — это ровно та беда,
    // из-за которой страница отставала от жизни.
    'Cache-Control': 'no-store'
  });
  ответ.end(тело);
}

/** Если добыча данных сломалась — говорим об этом прямо, а не показываем пустоту. */
function страницаОшибки(ошибка) {
  return '<!doctype html><meta charset="utf-8">'
    + '<title>Штаб — сбой</title>'
    + '<body style="font-family:system-ui;padding:24px;line-height:1.5">'
    + '<h1>Данные собрать не удалось</h1>'
    + '<p>Программа не смогла добыть данные и нарочно ничего не выдумывает.</p>'
    + '<p style="color:#A62A30"><b>Причина:</b> ' + String(ошибка && ошибка.message ? ошибка.message : ошибка) + '</p>'
    + '<p>Страница попробует ещё раз через 15 секунд.</p>'
    + '<script>setTimeout(function(){location.reload();},15000)</script>'
    + '</body>';
}

/**
 * Приводим адрес запроса к читаемому виду.
 * Русская буква в адресе приезжает по-разному: браузер шлёт её в записи
 * %D0%BA, а простые программы вроде curl — прямо байтами. Разбираем оба
 * случая, иначе адрес /кусок то работает, то нет.
 */
function разобратьАдрес(сырой) {
  let адрес = сырой;
  try {
    адрес = decodeURIComponent(сырой);
  } catch (ошибка) {
    адрес = сырой; // запись битая — работаем с тем, что прислали
  }
  if (/[\u0080-\u00FF]/.test(адрес)) {
    const перевод = Buffer.from(адрес, 'latin1').toString('utf8');
    if (перевод.indexOf('\uFFFD') === -1) адрес = перевод;
  }
  return адрес;
}

/** Достаём значение из адреса вида /ответ?запись=ключ&кнопка=да. */
function изАдреса(сырой, имяПоля) {
  const вопрос = сырой.indexOf('?');
  if (вопрос < 0) return null;
  const строка = разобратьАдрес(сырой.slice(вопрос + 1));
  const найдено = new RegExp(имяПоля + '=([^&]+)').exec(строка);
  return найдено ? найдено[1].trim() : null;
}

function часыСловами() {
  const с = new Date();
  const дв = function (ч) { return String(ч).padStart(2, '0'); };
  return дв(с.getDate()) + '.' + дв(с.getMonth() + 1) + ', ' + дв(с.getHours()) + ':' + дв(с.getMinutes());
}

/** Читаем маленький файл-словарь. Нет его — пустой словарь, не беда. */
function прочитатьСловарь(файл, поле) {
  try {
    const данные = JSON.parse(fs.readFileSync(файл, 'utf8'));
    return данные && данные[поле] ? данные[поле] : {};
  } catch (ошибка) {
    return {};
  }
}

/** Отмечаем, что владелец открывал запись: по этому на главной гаснет «новое». */
function отметитьПрочитанным(ключ) {
  const открыто = прочитатьСловарь(ФАЙЛ_ПРОЧИТАННОГО, 'открыто');
  if (открыто[ключ]) return; // уже отмечено — файл лишний раз не трогаем
  открыто[ключ] = часыСловами();
  try {
    fs.writeFileSync(ФАЙЛ_ПРОЧИТАННОГО, JSON.stringify({
      'что это': 'какие записи «Важного» владелец открывал и когда. Пишет сам дашборд.',
      открыто: открыто
    }, null, 2) + '\n', 'utf8');
  } catch (ошибка) {
    console.error('отметка о прочтении не записалась:', ошибка.message);
  }
}

/** Записываем ответ владельца. Время — из часов машины, не из запроса. */
function записатьОтвет(запись, кнопка) {
  const ответы = прочитатьСловарь(ФАЙЛ_ОТВЕТОВ, 'ответы');
  ответы[запись.ключ] = {
    кнопка: кнопка.ключ,
    имя: кнопка.имя,
    когда: часыСловами(),
    'когда точно': new Date().toISOString(),
    'на вопрос': запись.заголовок
  };
  try {
    fs.writeFileSync(ФАЙЛ_ОТВЕТОВ, JSON.stringify({
      'что это': 'ответы владельца на записи раздела «Важное». Пишет сам дашборд, руками сюда не надо.',
      ответы: ответы
    }, null, 2) + '\n', 'utf8');
    console.log('владелец ответил: ' + запись.ключ + ' → ' + кнопка.ключ + ' (' + часыСловами() + ')');
  } catch (ошибка) {
    console.error('ответ не записался:', ошибка.message);
  }
}

/** Нутро записи, если она рисуется кодом, а не текстом из файла. */
function особоеНутро(запись) {
  if (запись.особая === 'путь-до-партии') return разборПути.нутро();
  return null;
}

http.createServer(function (запрос, ответ) {
  // Работаем только на чтение: ничего, кроме GET, не принимаем.
  if (запрос.method !== 'GET' && запрос.method !== 'HEAD') {
    отдать(ответ, 405, 'text/plain; charset=utf-8', 'этот сервер только показывает страницу');
    return;
  }

  const адрес = разобратьАдрес(запрос.url.split('?')[0]);

  const целаяСтраница = (адрес === '/' || адрес === '/index.html');
  const толькоКусок = (адрес === '/кусок');

  // Старые адреса разбора: ссылку на него уже отправляли владельцу, поэтому
  // не ломаем её, а переводим на запись раздела «Важное».
  if (адрес === '/путь-до-партии' || адрес === '/выбор') {
    // В заголовке переадресации русские буквы недопустимы — их обязательно
    // кодировать, и «важное» тоже, иначе сервер падает на первой же ссылке.
    ответ.writeHead(302, {
      Location: '/' + encodeURIComponent('важное') + '/' + encodeURIComponent('путь-до-партии')
    });
    ответ.end();
    return;
  }

  // Все записи «Важного» одним списком.
  if (адрес === '/важное' || адрес === '/важное/') {
    отдать(ответ, 200, 'text/html; charset=utf-8', важное.страницаСписка());
    return;
  }

  // Одна запись. Открыл — значит прочитал, метка «новое» гаснет.
  if (адрес.startsWith('/важное/')) {
    const ключ = адрес.slice('/важное/'.length);
    const запись = важное.найтиЗапись(ключ);
    if (!запись) {
      отдать(ответ, 404, 'text/html; charset=utf-8', важное.страницаНеНашлась());
      return;
    }
    отметитьПрочитанным(запись.ключ);
    отдать(ответ, 200, 'text/html; charset=utf-8', важное.страницаЗаписи(запись, особоеНутро(запись)));
    return;
  }

  // Нажатие кнопки ответа. Из запроса берём только ключи, и оба сверяем
  // с записями: чего нет в файле штаба, того для сервера не существует.
  if (адрес === '/ответ') {
    const запись = важное.найтиЗапись(изАдреса(запрос.url, 'запись') || '');
    if (!запись) {
      отдать(ответ, 400, 'text/plain; charset=utf-8', 'нет такой записи');
      return;
    }
    const ключКнопки = изАдреса(запрос.url, 'кнопка');
    const кнопка = запись.кнопки.find(function (к) { return к.ключ === ключКнопки; });
    if (!кнопка) {
      отдать(ответ, 400, 'text/plain; charset=utf-8', 'у этой записи нет такой кнопки');
      return;
    }
    записатьОтвет(запись, кнопка);
    отдать(ответ, 200, 'text/html; charset=utf-8', важное.страницаПринято(запись, кнопка));
    return;
  }

  if (!целаяСтраница && !толькоКусок) {
    // Никаких файлов с диска: всё, чего нет в этом списке, просто не существует.
    отдать(ответ, 404, 'text/plain; charset=utf-8', 'здесь только дашборд: откройте /');
    return;
  }

  сбор.собратьВсё().then(function (данные) {
    // Раздел «Важное» собирается отдельно и кладётся в данные готовой
    // разметкой: так страница и «Важное» не ссылаются друг на друга по кругу.
    данные.важноеРазметка = важное.блокДляГлавной();
    if (толькоКусок) {
      отдать(ответ, 200, 'text/html; charset=utf-8', страница.внутренности(данные));
    } else {
      отдать(ответ, 200, 'text/html; charset=utf-8', страница.целаяСтраница(данные));
    }
  }).catch(function (ошибка) {
    console.error('не собрались данные:', ошибка && ошибка.message ? ошибка.message : ошибка);
    отдать(ответ, 500, 'text/html; charset=utf-8', страницаОшибки(ошибка));
  });
}).listen(ПОРТ, АДРЕС, function () {
  console.log('дашборд штаба поднят: http://' + АДРЕС + ':' + ПОРТ + '/');
  console.log('страница обновляется сама раз в 15 секунд; данные берутся заново при каждом запросе');
  console.log('слушает только этот компьютер, файлов с диска не отдаёт');
});
