/**
 * Приводим адрес запроса к читаемому виду.
 * Русская буква в адресе приезжает по-разному: браузер шлёт её в записи
 * %D0%BA, а простые программы вроде curl — прямо байтами. Разбираем оба
 * случая, иначе адрес /кусок то работает, то нет.
 */
function разобратьАдрес(сырой) {
  let адрес = сырой;
  try {
    адрес = decodeURIComponent(сырой);
  } catch (ошибка) {
    адрес = сырой; // запись битая — работаем с тем, что прислали
  }
  if (/[\u0080-\u00FF]/.test(адрес)) {
    const перевод = Buffer.from(адрес, 'latin1').toString('utf8');
    if (перевод.indexOf('\uFFFD') === -1) адрес = перевод;
  }
  return адрес;
}

/** Достаём значение из адреса вида /ответ?запись=ключ&кнопка=да. */
function изАдреса(сырой, имяПоля) {
  const вопрос = сырой.indexOf('?');
  if (вопрос < 0) return null;
  const строка = разобратьАдрес(сырой.slice(вопрос + 1));
  const найдено = new RegExp(имяПоля + '=([^&]+)').exec(строка);
  return найдено ? найдено[1].trim() : null;
}

function часыСловами() {
  const с = new Date();
  const дв = function (ч) { return String(ч).padStart(2, '0'); };
  return дв(с.getDate()) + '.' + дв(с.getMonth() + 1) + ', ' + дв(с.getHours()) + ':' + дв(с.getMinutes());
}

/** Читаем маленький файл-словарь. Нет его — пустой словарь, не беда. */
function прочитатьСловарь(файл, поле) {
  try {
    const данные = JSON.parse(fs.readFileSync(файл, 'utf8'));
    return данные && данные[поле] ? данные[поле] : {};
  } catch (ошибка) {
    return {};
  }
}

/** Отмечаем, что владелец открывал запись: по этому на главной гаснет «новое». */
function отметитьПрочитанным(ключ) {
  const открыто = прочитатьСловарь(ФАЙЛ_ПРОЧИТАННОГО, 'открыто');
  if (открыто[ключ]) return; // уже отмечено — файл лишний раз не трогаем
  открыто[ключ] = часыСловами();
  try {
    fs.writeFileSync(ФАЙЛ_ПРОЧИТАННОГО, JSON.stringify({
      'что это': 'какие записи «Важного» владелец открывал и когда. Пишет сам дашборд.',
      открыто: открыто
    }, null, 2) + '\n', 'utf8');
  } catch (ошибка) {
    console.error('отметка о прочтении не записалась:', ошибка.message);
  }
}

/** Записываем ответ владельца. Время — из часов машины, не из запроса. */
function записатьОтвет(запись, кнопка) {
  const ответы = прочитатьСловарь(ФАЙЛ_ОТВЕТОВ, 'ответы');
  ответы[запись.ключ] = {
    кнопка: кнопка.ключ,
    имя: кнопка.имя,
    когда: часыСловами(),
    'когда точно': new Date().toISOString(),
    'на вопрос': запись.заголовок
  };
  try {
    fs.writeFileSync(ФАЙЛ_ОТВЕТОВ, JSON.stringify({
      'что это': 'ответы владельца на записи раздела «Важное». Пишет сам дашборд, руками сюда не надо.',
      ответы: ответы
    }, null, 2) + '\n', 'utf8');
    console.log('владелец ответил: ' + запись.ключ + ' → ' + кнопка.ключ + ' (' + часыСловами() + ')');
  } catch (ошибка) {
    console.error('ответ не записался:', ошибка.message);
  }
}

/** Записываем письмо владельца — свободный текст, из формы «Написать штабу» / «Написать замечание». */
function записатьПисьмо(ключЗаписи, текст) {
  // Письма — список, а не словарь по ключу (по одной записи их может быть
  // несколько), поэтому читаем файл сами, а не через прочитатьСловарь.
  let письма;
  try {
    const данные = JSON.parse(fs.readFileSync(ФАЙЛ_ПИСЕМ, 'utf8'));
    письма = Array.isArray(данные.письма) ? данные.письма : [];
  } catch (ошибка) {
    письма = [];
  }
  письма.push({
    ключ: ключЗаписи || '',
    текст: текст,
    когда: часыСловами(),
    'когда точно': new Date().toISOString()
  });
  try {
    fs.writeFileSync(ФАЙЛ_ПИСЕМ, JSON.stringify({
      'что это': 'письма владельца штабу: свободный текст. Пустой «ключ» — письмо без привязки к записи «Важного», непустой — замечание к конкретной записи. Пишет сам дашборд, руками сюда не надо.',
      письма: письма
    }, null, 2) + '\n', 'utf8');
    console.log('владелец написал' + (ключЗаписи ? ' по записи ' + ключЗаписи : ' штабу без привязки') + ' (' + часыСловами() + ')');
  } catch (ошибка) {
    console.error('письмо не записалось:', ошибка.message);
  }
}

/* ---------------------------------------------------------------------------
   Картинки для записей «Важного»

   По правилам проекта этап показывается владельцу снимком. Страница видна
   из интернета через туннель, а в папке проекта лежит bot/.env с токеном,
   поэтому здесь два пояса проверки, и каждый держит сам:
     1. вид адреса — та же мерка, по которой запись решает, рисовать ли
        картинку (штаб/важное-страница.js, «разобратьПутьСнимка»);
     2. диск — настоящий путь (без ярлыков-ссылок) обязан лежать прямо
        в своей папке, и это обычный файл разумного размера.
   Не прошло хоть что-то — один и тот же отказ 404, без подробностей.
--------------------------------------------------------------------------- */

const КОРЕНЬ = path.resolve(path.join(__dirname, '..'));
const ТИПЫ_КАРТИНОК = { '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg' };
const ПРЕДЕЛ_КАРТИНКИ = 25 * 1024 * 1024;   // снимок экрана столько не весит; больше — не наш файл

/** Путь к картинке на диске по адресу запроса. Не годится — null. */
function файлКартинки(адрес) {
  const разбор = важное.разобратьПутьСнимка(адрес);
  if (!разбор) return null;
  let папка;
  let файл;
  try {
    папка = fs.realpathSync(path.join(КОРЕНЬ, разбор.папка));
    файл = fs.realpathSync(path.join(папка, разбор.имя));
  } catch (ошибка) {
    return null;   // нет такой папки или файла
  }
  if (path.dirname(файл) !== папка) return null;   // ярлык увёл за пределы папки
  let карточка;
  try {
    карточка = fs.lstatSync(файл);
  } catch (ошибка) {
    return null;
  }
  if (!карточка.isFile() || карточка.size > ПРЕДЕЛ_КАРТИНКИ) return null;
  if (!ТИПЫ_КАРТИНОК[path.extname(файл).toLowerCase()]) return null;
  return файл;
}

/** Отдать картинку. Её содержимое сервер не разбирает — только передаёт. */
function отдатьКартинку(запрос, ответ, файл) {
  const размер = fs.statSync(файл).size;
  ответ.writeHead(200, {
    'Content-Type': ТИПЫ_КАРТИНОК[path.extname(файл).toLowerCase()],
    'Content-Length': размер,
    'Cache-Control': 'no-store',          // снимок могли переснять под тем же именем
    'X-Content-Type-Options': 'nosniff'    // браузер не угадывает тип сам
  });
  if (запрос.method === 'HEAD') {
    ответ.end();
    return;
  }
  const поток = fs.createReadStream(файл);
  поток.on('error', function () { ответ.destroy(); });
  поток.pipe(ответ);
}

/** Нутро записи, если она рисуется кодом, а не текстом из файла. */
function особоеНутро(запись) {
  if (запись.особая === 'путь-до-партии') return разборПути.нутро();
  return null;
}

/* ---------------------------------------------------------------------------
   Пересборка списков раз в 5 минут

   Владелец: «сделай так, чтобы раз в 5 мин обновлялся дашборд полностью».
   Зовём ровно те программы, что штаб зовёт руками, — своей второй копии
   правил здесь нет. Они переписывают свои разделы ЗАДАЧИ.md: «Готово»,
   «В работе», «Ждём слова владельца», — и тем самым подтягивают публикации,
   ответы владельца и живость без участия штаба.

   Это обычные программы на этом компьютере: ни платных служб, ни лимита
   они не тратят. Пересборка идёт по часам, а не по запросу из браузера.
--------------------------------------------------------------------------- */

const ПРОГРАММЫ_ПЕРЕСБОРКИ = ['списки.js', 'в-работе.js', 'важное.js'];
const ШАГ_ПЕРЕСБОРКИ_МС = страница.ПЕРЕСБОРКА_МИН * 60 * 1000;
// Одна программа дольше минуты — значит зависла; снимаем, чтобы не копились.
const СРОК_ПРОГРАММЫ_МС = 60 * 1000;

/* Состояние пересборки. Время последней — из часов машины в ту минуту,
   когда пересборка закончилась, и никак иначе. */
const пересборка = { идёт: false, последняя: null, шаги: [], шагМин: страница.ПЕРЕСБОРКА_МИН };

/** Самая говорящая строка из вывода программы: ошибка, если она есть. */
function главнаяСтрока(вывод, ошибки, прошёл) {
  const строки = (String(вывод || '') + '\n' + String(ошибки || ''))
    .split(/\r?\n/)
    .map(function (с) { return с.trim(); })
    .filter(Boolean);
  if (!строки.length) return '';
  if (прошёл) return строки[0].slice(0, 200);
  const ошибка = строки.find(function (с) { return /^[A-Za-z]*Error:/.test(с); });
  return (ошибка || строки.slice(0, 2).join(' ')).slice(0, 200);
}

/** Запускаем одну программу штаба и ждём её конца. Не падаем ни при каком исходе. */
function запуститьПрограмму(имя) {
  return new Promise(function (готово) {
    execFile(process.execPath, [path.join(__dirname, имя)], {
      cwd: path.join(__dirname, '..'),
      timeout: СРОК_ПРОГРАММЫ_МС,
      windowsHide: true,
      maxBuffer: 1024 * 1024
    }, function (ошибка, вывод, ошибки) {
      const прошёл = !ошибка;
      готово({
        имя: имя,
        прошёл: прошёл,
        строка: прошёл ? главнаяСтрока(вывод, '', true)
          : (главнаяСтрока(вывод, ошибки, false) || String(ошибка.message || ошибка).slice(0, 200))
      });
    });
  });
}

/** Три программы по очереди: они правят один файл, вместе им нельзя. */
async function пересобрать() {
  if (пересборка.идёт) return; // прошлая ещё не кончилась — не накладываем
  пересборка.идёт = true;
  const шаги = [];
  try {
    for (const имя of ПРОГРАММЫ_ПЕРЕСБОРКИ) шаги.push(await запуститьПрограмму(имя));
  } finally {
    пересборка.шаги = шаги;
    пересборка.последняя = new Date();
    пересборка.идёт = false;
  }
  const сбои = шаги.filter(function (ш) { return !ш.прошёл; });
  console.log('пересобрано ' + часыСловами()
    + (сбои.length ? ' — не прошли: ' + сбои.map(function (ш) { return ш.имя + ' (' + ш.строка + ')'; }).join('; ') : ''));
}

/**
 * Пересборка с перехватом. Беда внутри неё не должна ронять весь дашборд:
 * необработанный отказ обещания в нынешнем Node гасит процесс целиком,
 * и владелец терял бы страницу из-за одной сломанной программы. Беду
 * кладём в сбои пересборки — её увидит полоса «Пересборка списков не прошла».
 */
function пересобратьБезПадения() {
  пересобрать().catch(function (ошибка) {
    const слова = String(ошибка && ошибка.message ? ошибка.message : ошибка).slice(0, 200);
    console.error('пересборка упала: ' + слова);
    пересборка.шаги = [{ имя: 'пересборка', прошёл: false, строка: слова }];
    пересборка.последняя = new Date();
    пересборка.идёт = false;
  });
}

/* ---------------------------------------------------------------------------
   Письмо словами: POST /сказать

   Единственная дверь, которая читает тело запроса, а не только адрес.
   Тело — обычная HTML-форма (application/x-www-form-urlencoded), без
   своего JavaScript: браузер отправляет её сам.

   Предел на тело — с большим запасом на процентную кодировку: кириллица
   в urlencoded виде — три символа на байт, поэтому даже 4000 знаков текста
   разрастаются в разы. Предел нужен не для текста (тот режется ниже до
   ПРЕДЕЛ_ТЕКСТА_ЗНАКОВ), а чтобы кто-то не завалил сервер гигабайтным телом.
--------------------------------------------------------------------------- */

const ПРЕДЕЛ_ТЕЛА_БАЙТ = 200 * 1024;      // с запасом на percent-encoding кириллицы
const ПРЕДЕЛ_ТЕКСТА_ЗНАКОВ = 4000;

/** Принимаем письмо: читаем тело, проверяем поля, пишем в файл или отказываем словами. */
function принятьПисьмо(запрос, ответ) {
  const части = [];
  let набралБайт = 0;
  let слишкомДлинное = false;

  запрос.on('data', function (кусок) {
    набралБайт += кусок.length;
    if (набралБайт > ПРЕДЕЛ_ТЕЛА_БАЙТ) {
      слишкомДлинное = true;
      return; // дальше не копим — лишнее всё равно не понадобится
    }
    части.push(кусок);
  });

  запрос.on('error', function () {
    // Соединение оборвалось на середине — ответ уже никто не примет.
  });

  запрос.on('end', function () {
    if (слишкомДлинное) {
      отдать(ответ, 413, 'text/plain; charset=utf-8', 'сообщение слишком длинное, отправьте короче');
      return;
    }

    let поля;
    try {
      поля = new URLSearchParams(Buffer.concat(части).toString('utf8'));
    } catch (ошибка) {
      отдать(ответ, 400, 'text/plain; charset=utf-8', 'не удалось разобрать отправленное');
      return;
    }

    const ключЗаписи = String(поля.get('запись') || '').trim();
    const текст = String(поля.get('текст') || '').trim().slice(0, ПРЕДЕЛ_ТЕКСТА_ЗНАКОВ);

    let запись = null;
    if (ключЗаписи) {
      запись = важное.найтиЗапись(ключЗаписи);
      if (!запись) {
        отдать(ответ, 400, 'text/plain; charset=utf-8', 'нет такой записи «Важного» — письмо не сохранено');
        return;
      }
    }

    if (!текст) {
      отдать(ответ, 400, 'text/plain; charset=utf-8', 'текст пуст — писать нечего, письмо не сохранено');
      return;
    }

    записатьПисьмо(ключЗаписи, текст);
    отдать(ответ, 200, 'text/html; charset=utf-8', важное.страницаПисьмоЗаписано(запись));
  });
}

http.createServer(function (запрос, ответ) {
  const адрес = разобратьАдрес(запрос.url.split('?')[0]);

  // Единственное, что сервер принимает, помимо чтения, — письмо словами.
  if (запрос.method === 'POST') {
    if (адрес === '/сказать') {
      принятьПисьмо(запрос, ответ);
      return;
    }
    отдать(ответ, 405, 'text/plain; charset=utf-8', 'этот сервер принимает данные только по адресу /сказать');
    return;
  }

  // Всё остальное — только на чтение.
  if (запрос.method !== 'GET' && запрос.method !== 'HEAD') {
    отдать(ответ, 405, 'text/plain; charset=utf-8', 'этот сервер только показывает страницу');
    return;
  }

  const целаяСтраница = (адрес === '/' || адрес === '/index.html');
  const толькоКусок = (адрес === '/кусок');

  // Старые адреса разбора: ссылку на него уже отправляли владельцу, поэтому
  // не ломаем её, а переводим на запись раздела «Важное».
  if (адрес === '/путь-до-партии' || адрес === '/выбор') {
    // В заголовке переадресации русские буквы недопустимы — их обязательно
    // кодировать, и «важное» тоже, иначе сервер падает на первой же ссылке.
    ответ.writeHead(302, {
      Location: '/' + encodeURIComponent('важное') + '/' + encodeURIComponent('путь-до-партии')
    });
    ответ.end();
    return;
  }

  // «Жив ли сервер» — одно слово, без сбора данных. Этим вопросом страница
  // проверяет связь перед полной перезагрузкой (см. штаб/страница.js).
  if (адрес === '/жив') {
    отдать(ответ, 200, 'text/plain; charset=utf-8', 'жив');
    return;
  }

  // Картинки для записей — единственные файлы с диска, и только по мерке выше.
  if (важное.ПАПКИ_СНИМКОВ.some(function (п) { return адрес.startsWith('/' + п + '/'); })) {
    const файл = файлКартинки(адрес);
    if (!файл) {
      отдать(ответ, 404, 'text/plain; charset=utf-8', 'такой картинки нет');
      return;
    }
    отдатьКартинку(запрос, ответ, файл);
    return;
  }

  // Задания для ChatGPT: открытые сверху, решённые ниже.
  if (адрес === важное.АДРЕС_ЗАДАНИЙ || адрес === важное.АДРЕС_ЗАДАНИЙ + '/') {
    отдать(ответ, 200, 'text/html; charset=utf-8', важное.страницаЗаданий());
    return;
  }

  // Все записи «Важного» одним списком.
  if (адрес === '/важное' || адрес === '/важное/') {
    отдать(ответ, 200, 'text/html; charset=utf-8', важное.страницаСписка());
    return;
  }

  // Одна запись. Открыл — значит прочитал, метка «новое» гаснет.
  if (адрес.startsWith('/важное/')) {
    const ключ = адрес.slice('/важное/'.length);
    const запись = важное.найтиЗапись(ключ);
    if (!запись) {
      отдать(ответ, 404, 'text/html; charset=utf-8', важное.страницаНеНашлась());
      return;
    }
    отметитьПрочитанным(запись.ключ);
    отдать(ответ, 200, 'text/html; charset=utf-8', важное.страницаЗаписи(запись, особоеНутро(запись)));
    return;
  }

  // Нажатие кнопки ответа. Из запроса берём только ключи, и оба сверяем
  // с записями: чего нет в файле штаба, того для сервера не существует.
  if (адрес === '/ответ') {
    const запись = важное.найтиЗапись(изАдреса(запрос.url, 'запись') || '');
    if (!запись) {
      отдать(ответ, 400, 'text/plain; charset=utf-8', 'нет такой записи');
      return;
    }
    const ключКнопки = изАдреса(запрос.url, 'кнопка');
    const кнопка = запись.кнопки.find(function (к) { return к.ключ === ключКнопки; });
    if (!кнопка) {
      отдать(ответ, 400, 'text/plain; charset=utf-8', 'у этой записи нет такой кнопки');
      return;
    }
    записатьОтвет(запись, кнопка);
    отдать(ответ, 200, 'text/html; charset=utf-8', важное.страницаПринято(запись, кнопка));
    return;
  }

  if (!целаяСтраница && !толькоКусок) {
    // Никаких файлов с диска: всё, чего нет в этом списке, просто не существует.
    отдать(ответ, 404, 'text/plain; charset=utf-8', 'здесь только дашборд: откройте /');
    return;
  }

  сбор.собратьВсё().then(function (данные) {
    // Раздел «Важное» собирается отдельно и кладётся в данные готовой
    // разметкой: так страница и «Важное» не ссылаются друг на друга по кругу.
    данные.важноеРазметка = важное.блокДляГлавной();
    данные.кнопкаЗаданий = важное.кнопкаЗаданий();
    данные.пересборка = пересборка;
    if (толькоКусок) {
      отдать(ответ, 200, 'text/html; charset=utf-8', страница.внутренности(данные));
    } else {
      отдать(ответ, 200, 'text/html; charset=utf-8', страница.целаяСтраница(данные));
    }
  }).catch(function (ошибка) {
    console.error('не собрались данные:', ошибка && ошибка.message ? ошибка.message : ошибка);
    отдать(ответ, 500, 'text/html; charset=utf-8', страницаОшибки(ошибка));
  });
}).listen(ПОРТ, АДРЕС, function () {
  console.log('дашборд штаба поднят: http://' + АДРЕС + ':' + ПОРТ + '/');
  console.log('страница обновляется сама раз в 15 секунд; данные берутся заново при каждом запросе');
  console.log('списки пересобираются сами раз в ' + страница.ПЕРЕСБОРКА_МИН + ' минут: ' + ПРОГРАММЫ_ПЕРЕСБОРКИ.join(', '));
  console.log('слушает только этот компьютер; с диска отдаёт только картинки png и jpg из снимки/ и эталон/');
  // Первая пересборка — сразу, не ждать пять минут после запуска.
  пересобратьБезПадения();
  setInterval(пересобратьБезПадения, ШАГ_ПЕРЕСБОРКИ_МС);
});
