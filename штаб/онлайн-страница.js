/** Настоящий вызов хаба: выполнить скрипт на ВМ (ленивый require — штаб/вм.js нужен только здесь). */
function спроситьХабНастоящий(текстСкрипта, срокМс) {
  // Свой срок у хаба короче срока обещания на 2 с: хаб всегда заканчивает сам
  // раньше, чем мы махнём рукой, и «сирот» после обрыва не остаётся.
  return require('./вм.js').выполнитьСкрипт(ИД_БОЕВОЙ_МАШИНЫ, текстСкрипта, { срокМс: Math.max(1000, срокМс - 2000) });
}

/** Разобрать то, что скрипт напечатал на ВМ: { сводка } либо { ошибка }. */
function разобратьВыводВМ(вывод) {
  const текст = String(вывод === null || вывод === undefined ? '' : вывод);
  const разрыв = текст.indexOf('\n');
  const метка = (разрыв === -1 ? текст : текст.slice(0, разрыв)).trim();
  if (метка === 'НЕТ_КЛЮЧА') return { ошибка: ТЕКСТ_НЕТ_КЛЮЧА_ВМ };
  if (метка === 'ГОТОВО') {
    try {
      return { сводка: JSON.parse(текст.slice(разрыв + 1)) };
    } catch (сбой) {
      return { ошибка: ТЕКСТ_СЕРВЕР_ВМ_МОЛЧИТ };
    }
  }
  if (метка.indexOf('СЕРВЕР_КОД_') === 0) return { ошибка: ТЕКСТ_СЕРВЕР_ВМ_МОЛЧИТ };
  // Вывода со знакомой меткой нет — скрипт до машины не дошёл или машина промолчала.
  return { ошибка: ТЕКСТ_ХАБ_МОЛЧИТ };
}

/**
 * Один вызов хаба со своим пределом ожидания: что бы ни случилось (хаб завис,
 * упал, вернул мусор), промис решится и вернёт { сводка } либо { ошибка }.
 * Довод настройки.хаб (функция скрипт→{вывод}) — только для проверок.
 */
function спроситьВМ(настройки) {
  const хаб = (настройки && настройки.хаб) || спроситьХабНастоящий;
  const срокМс = (настройки && Number.isFinite(настройки.срокХабаМс)) ? настройки.срокХабаМс : СРОК_ХАБА_МС;
  return new Promise(function (готово) {
    let решено = false;
    function решить(итог) { if (!решено) { решено = true; clearTimeout(таймер); готово(итог); } }
    const таймер = setTimeout(function () { решить({ ошибка: ТЕКСТ_ХАБ_МОЛЧИТ }); }, срокМс);
    // catch стоит в конце цепочки: он ловит и отказ хаба, и сбой самого разбора ответа.
    Promise.resolve().then(function () { return хаб(СКРИПТ_ДЛЯ_ВМ, срокМс); })
      .then(function (результат) { решить(разобратьВыводВМ(результат && результат.вывод)); })
      .catch(function () { решить({ ошибка: ТЕКСТ_ХАБ_МОЛЧИТ }); });
  });
}

/* Память дашборда о боевой машине: последняя удачная сводка, когда она
   получена, последняя беда и идущий сейчас вызов (один на всех). */
const кэшВМ = { сводка: null, когда: 0, ошибка: null, попытка: null, идёт: null };

/** Забыть всё известное о ВМ — нужно проверкам. */
function сброситьКэшВМ() {
  кэшВМ.сводка = null;
  кэшВМ.когда = 0;
  кэшВМ.ошибка = null;
  кэшВМ.попытка = null;
  кэшВМ.идёт = null;
}

function начатьОбновлениеВМ(настройки, часы) {
  кэшВМ.попытка = часы();
  кэшВМ.идёт = спроситьВМ(настройки).then(function (итог) {
    if (итог.сводка) {
      кэшВМ.сводка = итог.сводка;
      кэшВМ.когда = часы();
      кэшВМ.ошибка = null;
    } else {
      кэшВМ.ошибка = итог.ошибка;
    }
    кэшВМ.идёт = null;
  });
}

/** «ЧЧ:ММ» по часам этого компьютера (где крутится дашборд). */
function времяСловами(мс) {
  const д = new Date(мс);
  return String(д.getHours()).padStart(2, '0') + ':' + String(д.getMinutes()).padStart(2, '0');
}

/**
 * Данные с боевой машины. Хаб зовём не чаще раза в ПЕРИОД_ОБНОВЛЕНИЯ_ВМ_МС
 * (считая и неудачные попытки), а страница ждёт его недолго: не успел —
 * отдаём последнее известное. Возвращает { сводка, пометка } либо { ошибка }.
 */
async function сводкаСВМ(настройки) {
  const часы = (настройки && typeof настройки.часы === 'function') ? настройки.часы : Date.now;
  const ждатьМс = (настройки && Number.isFinite(настройки.ждатьХабМс)) ? настройки.ждатьХабМс : ЖДАТЬ_ХАБ_НА_СТРАНИЦЕ_МС;

  // Часы скакнули назад — «прошло меньше минуты» было бы вечным, обновление встало бы.
  const пора = кэшВМ.попытка === null || часы() < кэшВМ.попытка || часы() - кэшВМ.попытка >= ПЕРИОД_ОБНОВЛЕНИЯ_ВМ_МС;
  if (!кэшВМ.идёт && пора) начатьОбновлениеВМ(настройки, часы);

  if (кэшВМ.идёт) {
    let таймер = null;
    const предел = new Promise(function (готово) {
      таймер = setTimeout(готово, ждатьМс);
    });
    await Promise.race([кэшВМ.идёт, предел]);
    clearTimeout(таймер);
  }

  if (кэшВМ.сводка) {
    const пометка = кэшВМ.ошибка
      ? 'боевой сервер не ответил, данные на ' + времяСловами(кэшВМ.когда) + ' (' + кэшВМ.ошибка + ')'
      : 'данные на ' + времяСловами(кэшВМ.когда);
    return { сводка: кэшВМ.сводка, пометка: пометка };
  }
  if (кэшВМ.ошибка) return { ошибка: кэшВМ.ошибка };
  return { ошибка: ТЕКСТ_СПРАШИВАЮ };
}

/**
 * Откуда брать сводку. Порт задан явно — только местный сервер (так живут
 * проверки). Иначе — только боевая машина через хаб: местный 8790 не
 * спрашиваем вовсе, там может сидеть старая пустая копия, которая отвечает,
 * но никого не видит (так «никто не заходил» врало владельцу 02.10).
 */
async function получитьСводку(настройки) {
  if (портЗадан(настройки)) return запросСводки(настройки);
  return сводкаСВМ(настройки);
}

