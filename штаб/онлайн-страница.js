/* Страница дашборда «Онлайн»: кто сейчас в игре, кто заходил сегодня и
   за 7 дней. Задание: штаб/план-онлайн-дашборд.md, разделы «Главное» и
   «Этап 4».

   ЗАЩИТА (читать обязательно, если будете это править).
   Дашборд открыт наружу туннелем без пароля — здесь же номера Telegram
   игроков, которых наружу выпускать нельзя. Поэтому два независимых
   замка́:

   1. Эта страница отвечает 403 всякому запросу, в котором есть хоть один
      заголовок туннеля или nginx (cf-connecting-ip, cf-ray,
      x-forwarded-for, x-real-ip) — то есть запрос пришёл не с этого же
      компьютера. Список заголовков — тот же, что в server/сервер.js
      (ЗАГОЛОВКИ_ТУННЕЛЯ): туда же смотрит сервер комнат для маршрута
      /штаб-онлайн, здесь — независимая вторая проверка на своей стороне.

   2. Сервер комнат (server/сервер.js, GET /штаб-онлайн) сам отдаёт сводку
      только с верным ключом в заголовке x-klyuch-shtaba (латиницей —
      кириллица в имени HTTP-заголовка запрещена, Node такой запрос не
      отправит). Ключ читается из того же файла, что создаёт сервер —
      server/данные/ключ-штаба, путь берётся тем же способом
      (server/папка-данных.js), поэтому переезд папки данных через
      переменную ДАННЫЕ_ИГРЫ/GAMES_DATA работает одинаково для сервера
      и для дашборда. Ключ НИКОГДА не попадает в HTML и не пишется в
      ответ — только в заголовок исходящего запроса.

   Порт сервера комнат — 8790 по умолчанию, его можно переопределить
   переменной окружения ПОРТ_СЕРВЕРА_КОМНАТ (нужно проверкам: боевой
   8790 они не трогают, поднимают свою копию на свободном порту). */

'use strict';

const fs = require('fs');
const http = require('http');
const гдеДанные = require('../server/папка-данных.js');
const страница = require('./страница.js');

/* Имя заголовка — то же самое, что в server/сервер.js (ЗАГОЛОВОК_КЛЮЧА_ШТАБА). */
const ЗАГОЛОВОК_КЛЮЧА_ШТАБА = 'x-klyuch-shtaba';

/* Те же имена, что ЗАГОЛОВКИ_ТУННЕЛЯ в server/сервер.js. */
const ЗАГОЛОВКИ_ТУННЕЛЯ = ['cf-connecting-ip', 'cf-ray', 'x-forwarded-for', 'x-real-ip'];

const ИМЯ_ПЕРЕМЕННОЙ_ПОРТА = 'ПОРТ_СЕРВЕРА_КОМНАТ';
const ПОРТ_ПО_УМОЛЧАНИЮ = 8790;
const СРОК_ОТВЕТА_МС = 2500;

function э(текст) {
  return String(текст === null || текст === undefined ? '' : текст)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;')
    .replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

/** Пришёл ли запрос через туннель или nginx — то же правило, что у сервера комнат. */
function пришёлСнаружи(запрос) {
  const заголовки = (запрос && запрос.headers) || {};
  return ЗАГОЛОВКИ_ТУННЕЛЯ.some(function (имя) { return заголовки[имя] !== undefined; });
}

/** Порт сервера комнат: явный довод (для проверок) → переменная окружения → 8790. */
function порт(настройки) {
  if (настройки && Number.isFinite(настройки.порт) && настройки.порт > 0) return настройки.порт;
  const изПеременной = Number(process.env[ИМЯ_ПЕРЕМЕННОЙ_ПОРТА]);
  return Number.isFinite(изПеременной) && изПеременной > 0 ? изПеременной : ПОРТ_ПО_УМОЛЧАНИЮ;
}

/** Ключ штаба с диска. Файла нет или он пуст — null (честно скажем об этом на экране). */
function прочитатьКлюч() {
  try {
    const текст = fs.readFileSync(гдеДанные.файл('ключ-штаба'), 'utf8').trim();
    return текст || null;
  } catch (сбой) {
    return null;
  }
}

/**
 * Спросить сервер комнат. Возвращает { сводка } либо { ошибка: строка }.
 * Ключ никогда не попадает в возвращаемое значение.
 */
function запросСводки(настройки) {
  return new Promise(function (готово) {
    const ключ = прочитатьКлюч();
    if (!ключ) {
      готово({ ошибка: 'файла с ключом доступа ещё нет — сервер комнат его не создал (сервер не отвечает)' });
      return;
    }
    const срокМс = (настройки && Number.isFinite(настройки.таймаутМс)) ? настройки.таймаутМс : СРОК_ОТВЕТА_МС;
    const адрес = 'http://127.0.0.1:' + порт(настройки) + '/штаб-онлайн';
    let запрос;
    try {
      запрос = http.get(адрес, { timeout: срокМс, headers: { [ЗАГОЛОВОК_КЛЮЧА_ШТАБА]: ключ } }, function (ответ) {
        let тело = '';
        ответ.setEncoding('utf8');
        ответ.on('data', function (кусок) { if (тело.length < 200000) тело += кусок; });
        ответ.on('end', function () {
          if (ответ.statusCode !== 200) {
            готово({ ошибка: 'сервер не отвечает как надо (код ' + ответ.statusCode + ')' });
            return;
          }
          try {
            готово({ сводка: JSON.parse(тело) });
          } catch (сбой) {
            готово({ ошибка: 'сервер не отвечает (ответ не понят)' });
          }
        });
      });
    } catch (сбой) {
      готово({ ошибка: 'сервер не отвечает' });
      return;
    }
    запрос.on('timeout', function () { запрос.destroy(); });
    запрос.on('error', function () { готово({ ошибка: 'сервер не отвечает' }); });
  });
}

/* ---------------------------------------------------------------------------
   Разметка экрана
--------------------------------------------------------------------------- */

function рядСейчас(человек) {
  return '<li class="онлайн-сейчас-строка">'
    + '<b>' + э(человек.имя || 'без имени') + '</b>'
    + ' · ' + э(человек.игра || '')
    + ' · ' + (Number.isFinite(человек.минут) ? человек.минут : 0) + ' мин</li>';
}

/** «дурак 12 мин, шашки 3 мин» из минутыПоИграм. */
function играмиСловами(минутыПоИграм) {
  const части = Object.keys(минутыПоИграм || {}).map(function (игра) {
    return игра + ' ' + минутыПоИграм[игра] + ' мин';
  });
  return части.length ? части.join(', ') : '—';
}

function рядПериода(человек) {
  return '<tr>'
    + '<td>' + э(человек.имя || 'без имени') + '</td>'
    + '<td>' + (Number.isFinite(человек.заходов) ? человек.заходов : 0) + '</td>'
    + '<td>' + (Number.isFinite(человек.минут) ? человек.минут : 0) + ' мин</td>'
    + '<td>' + э(играмиСловами(человек.минутыПоИграм)) + '</td>'
    + '</tr>';
}

function таблицаПериода(id, активна, список) {
  const класс = 'онлайн-вкладка' + (активна ? ' онлайн-вкладка--активна' : '');
  if (!список.length) {
    return '<div class="' + класс + '" id="' + id + '"><p class="онлайн-пусто">Пока никто не заходил.</p></div>';
  }
  const строки = список.map(рядПериода).join('');
  return '<div class="' + класс + '" id="' + id + '">'
    + '<table class="онлайн-таблица"><thead><tr>'
    + '<th>Имя</th><th>Заходов</th><th>Время</th><th>Во что играл</th>'
    + '</tr></thead><tbody>' + строки + '</tbody></table></div>';
}

/** Разметка при удачном ответе сервера — числа и списки из сводка(). */
function содержимоеУспеха(сводка) {
  const сейчас = Array.isArray(сводка && сводка.сейчас) ? сводка.сейчас : [];
  const сегодня = Array.isArray(сводка && сводка.сегодня) ? сводка.сегодня : [];
  const неделя = Array.isArray(сводка && сводка.неделя) ? сводка.неделя : [];

  const списокСейчас = сейчас.length
    ? '<ul class="онлайн-список">' + сейчас.map(рядСейчас).join('') + '</ul>'
    : '<p class="онлайн-пусто">Сейчас никого нет.</p>';

  return '<h2>Сейчас онлайн: ' + сейчас.length + '</h2>'
    + списокСейчас
    + '<div class="онлайн-вкладки-кнопки">'
    + '<button type="button" class="онлайн-вкладка-кнопка онлайн-вкладка-кнопка--активна" '
    + 'onclick="показатьВкладкуОнлайн(this,\'вкладка-сегодня\')">Сегодня</button>'
    + '<button type="button" class="онлайн-вкладка-кнопка" '
    + 'onclick="показатьВкладкуОнлайн(this,\'вкладка-неделя\')">7 дней</button>'
    + '</div>'
    + таблицаПериода('вкладка-сегодня', true, сегодня)
    + таблицаПериода('вкладка-неделя', false, неделя);
}

