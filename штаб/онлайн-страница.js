/* Страница дашборда «Онлайн»: кто сейчас в игре, кто заходил сегодня и
   за 7 дней. Задание: штаб/план-онлайн-дашборд.md, разделы «Главное» и
   «Этап 4».

   ЗАЩИТА (читать обязательно, если будете это править).
   Дашборд открыт наружу туннелем без пароля — здесь же номера Telegram
   игроков, которых наружу выпускать нельзя. Поэтому два независимых
   замка́:

   1. Эта страница отвечает 403 всякому запросу, в котором есть хоть один
      заголовок туннеля или nginx (cf-connecting-ip, cf-ray,
      x-forwarded-for, x-real-ip) — то есть запрос пришёл не с этого же
      компьютера. Список заголовков — тот же, что в server/сервер.js
      (ЗАГОЛОВКИ_ТУННЕЛЯ): туда же смотрит сервер комнат для маршрута
      /штаб-онлайн, здесь — независимая вторая проверка на своей стороне.

   2. Сервер комнат (server/сервер.js, GET /штаб-онлайн) сам отдаёт сводку
      только с верным ключом в заголовке x-klyuch-shtaba (латиницей —
      кириллица в имени HTTP-заголовка запрещена, Node такой запрос не
      отправит). Ключ читается из того же файла, что создаёт сервер —
      server/данные/ключ-штаба, путь берётся тем же способом
      (server/папка-данных.js), поэтому переезд папки данных через
      переменную ДАННЫЕ_ИГРЫ/GAMES_DATA работает одинаково для сервера
      и для дашборда. Ключ НИКОГДА не попадает в HTML и не пишется в
      ответ — только в заголовок исходящего запроса.

   Порт сервера комнат — 8790 по умолчанию, его можно переопределить
   переменной окружения ПОРТ_СЕРВЕРА_КОМНАТ (нужно проверкам: боевой
   8790 они не трогают, поднимают свою копию на свободном порту).

   БОЕВАЯ МАШИНА. С 23.09 боевой сервер комнат живёт не на этом
   компьютере, а на ВМ (Ubuntu, /srv/games, служба games-server, порт
   8790 только внутри ВМ). Поэтому, если порт явно не задан (ни доводом,
   ни переменной), страница спрашивает ТОЛЬКО ВМ через хаб, а местный
   8790 не спрашивает вовсе (на нём может висеть старая пустая копия,
   которая отвечает «никого нет»). Явно заданный порт — только местный
   сервер, как у проверок. Хаб (штаб/вм.js): на ВМ запускается короткий скрипт, который берёт
   ключ штаба из файла на самой ВМ и делает тот же запрос. Ключ с ВМ не
   уезжает: наружу идёт только JSON ответа, и в нём уже вырезаны номера
   игроков (хаб хранит всё напечатанное в истории запусков). Хаб отвечает несколько секунд,
   поэтому ответ держим в памяти, обновляем не чаще раза в минуту, а
   страница ждёт хаб недолго и, если не успел, отдаёт последнее известное. */

'use strict';

const fs = require('fs');
const http = require('http');
const гдеДанные = require('../server/папка-данных.js');
const страница = require('./страница.js');

/* Имя заголовка — то же самое, что в server/сервер.js (ЗАГОЛОВОК_КЛЮЧА_ШТАБА). */
const ЗАГОЛОВОК_КЛЮЧА_ШТАБА = 'x-klyuch-shtaba';

/* Те же имена, что ЗАГОЛОВКИ_ТУННЕЛЯ в server/сервер.js. */
const ЗАГОЛОВКИ_ТУННЕЛЯ = ['cf-connecting-ip', 'cf-ray', 'x-forwarded-for', 'x-real-ip'];

const ИМЯ_ПЕРЕМЕННОЙ_ПОРТА = 'ПОРТ_СЕРВЕРА_КОМНАТ';
const ПОРТ_ПО_УМОЛЧАНИЮ = 8790;
const СРОК_ОТВЕТА_МС = 2500;

/* Номер боевой машины (ВМ с сервером комнат) в хабе RMM — тот же, что в
   штаб/вм.js «выполнить <id>». Список машин: node штаб/вм.js устройства. */
const ИД_БОЕВОЙ_МАШИНЫ = 'ea35b08f-8826-47e4-b0e9-ee27e032eda3';

/* Папка данных сервера НА ВМ (там службе games-server задано
   GAMES_DATA=этой папке). Файл ключа штаба лежит в ней. */
const ПАПКА_ДАННЫХ_НА_ВМ = '/srv/games/server/данные';

const ПЕРИОД_ОБНОВЛЕНИЯ_ВМ_МС = 60000;  // хаб не дёргаем чаще раза в минуту
const СРОК_ХАБА_МС = 45000;             // дольше хаб не ждём вовсе
const ЖДАТЬ_ХАБ_НА_СТРАНИЦЕ_МС = 2000;  // столько страница готова ждать хаб

/* Тексты про боевую машину — три разных беды, три разных слова. */
const ТЕКСТ_ХАБ_МОЛЧИТ = 'хаб не отвечает — до боевой машины не достучаться';
const ТЕКСТ_СЕРВЕР_ВМ_МОЛЧИТ = 'сервер комнат на боевой машине не отвечает';
const ТЕКСТ_НЕТ_КЛЮЧА_ВМ = 'ключа штаба на боевой машине нет';
const ТЕКСТ_СПРАШИВАЮ = 'спрашиваю боевую машину…';

/* Программа для node на ВМ: читает JSON со стандартного входа, рекурсивно
   выкидывает поле «номер» (номер игрока в Telegram) и печатает то, что
   осталось. Зачем: всё, что скрипт печатает на ВМ, хаб хранит в истории
   запусков, а номера игроков туда попадать не должны; странице они не нужны
   (в разметке есть только имя, игра и минуты). Внутри только двойные
   кавычки — программа вставляется в bash между одинарными. */
const ПРОГРАММА_БЕЗ_НОМЕРОВ = 'const f=(в)=>Array.isArray(в)?в.map(f):(в&&typeof в==="object"'
  + '?Object.fromEntries(Object.entries(в).filter((п)=>п[0]!=="номер").map((п)=>[п[0],f(п[1])])):в);'
  + 'process.stdout.write(JSON.stringify(f(JSON.parse(require("fs").readFileSync(0,"utf8")))));';

/* Скрипт для ВМ (bash). Печатает первой строкой метку, дальше — тело ответа:
     НЕТ_КЛЮЧА / СЕРВЕР_КОД_<код> / ГОТОВО (и следом JSON без номеров игроков).
   Ключ читается на ВМ и уходит в curl через временный «файл» заголовков
   (-H @…), а не в командной строке, чтобы не светиться в списке процессов.
   Ответ сервера держим в переменной, а не во временном файле: нечего
   забывать удалять. Код ответа curl приписывает в хвост после «~~», и мы
   его отрезаем (не «@@»: значение -w, начинающееся с «@», curl принимает
   за имя файла и падает). Сырой ответ наружу не печатается никогда — только то, что
   прошло через ПРОГРАММА_БЕЗ_НОМЕРОВ; не смогла node — честная метка сбоя.
   Имена переменных — только латиницей: bash на ВМ кириллицу в именах не
   принимает. Путь в адресе — процентами: «штаб-онлайн». */
const СКРИПТ_ДЛЯ_ВМ = [
  '#!/bin/bash',
  'KEYFILE="' + ПАПКА_ДАННЫХ_НА_ВМ + '/ключ-штаба"',
  'if [ ! -s "$KEYFILE" ]; then echo "НЕТ_КЛЮЧА"; exit 0; fi',
  'KEY=$(tr -d " \\r\\n" < "$KEYFILE")',
  'RESP=$(curl -sS -m 8 -w "~~%{http_code}" -H @<(printf "' + ЗАГОЛОВОК_КЛЮЧА_ШТАБА + ': %s\\n" "$KEY") "http://127.0.0.1:8790/%D1%88%D1%82%D0%B0%D0%B1-%D0%BE%D0%BD%D0%BB%D0%B0%D0%B9%D0%BD" 2>/dev/null)',
  'CODE="${RESP##*~~}"',
  'BODY="${RESP%~~*}"',
  'if [ "$CODE" != "200" ]; then echo "СЕРВЕР_КОД_$CODE"; exit 0; fi',
  'OUT=$(printf \'%s\' "$BODY" | node -e \'' + ПРОГРАММА_БЕЗ_НОМЕРОВ + '\' 2>/dev/null)',
  'if [ -z "$OUT" ]; then echo "СЕРВЕР_КОД_РАЗБОР"; exit 0; fi',
  'echo "ГОТОВО"',
  'echo "$OUT"'
].join('\n') + '\n';

function э(текст) {
  return String(текст === null || текст === undefined ? '' : текст)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;')
    .replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

/** Пришёл ли запрос через туннель или nginx — то же правило, что у сервера комнат. */
function пришёлСнаружи(запрос) {
  const заголовки = (запрос && запрос.headers) || {};
  return ЗАГОЛОВКИ_ТУННЕЛЯ.some(function (имя) { return заголовки[имя] !== undefined; });
}

/** Задан ли порт явно (довод для проверок или переменная окружения)? */
function портЗадан(настройки) {
  if (настройки && Number.isFinite(настройки.порт) && настройки.порт > 0) return true;
  const изПеременной = Number(process.env[ИМЯ_ПЕРЕМЕННОЙ_ПОРТА]);
  return Number.isFinite(изПеременной) && изПеременной > 0;
}

/** Порт сервера комнат: явный довод (для проверок) → переменная окружения → 8790.
 *  Довод настройки.портПоУмолчанию — только для проверок: подменяет «8790»,
 *  не считаясь явно заданным портом (чтобы не трогать настоящий 8790). */
function порт(настройки) {
  if (настройки && Number.isFinite(настройки.порт) && настройки.порт > 0) return настройки.порт;
  const изПеременной = Number(process.env[ИМЯ_ПЕРЕМЕННОЙ_ПОРТА]);
  if (Number.isFinite(изПеременной) && изПеременной > 0) return изПеременной;
  return (настройки && Number.isFinite(настройки.портПоУмолчанию)) ? настройки.портПоУмолчанию : ПОРТ_ПО_УМОЛЧАНИЮ;
}

/** Ключ штаба с диска. Файла нет или он пуст — null (честно скажем об этом на экране). */
function прочитатьКлюч() {
  try {
    const текст = fs.readFileSync(гдеДанные.файл('ключ-штаба'), 'utf8').trim();
    return текст || null;
  } catch (сбой) {
    return null;
  }
}

/**
 * Спросить сервер комнат. Возвращает { сводка } либо { ошибка: строка }.
 * Ключ никогда не попадает в возвращаемое значение.
 */
function запросСводки(настройки) {
  return new Promise(function (готово) {
    const ключ = прочитатьКлюч();
    if (!ключ) {
      готово({ ошибка: 'файла с ключом доступа ещё нет — сервер комнат его не создал (сервер не отвечает)' });
      return;
    }
    const срокМс = (настройки && Number.isFinite(настройки.таймаутМс)) ? настройки.таймаутМс : СРОК_ОТВЕТА_МС;
    const адрес = 'http://127.0.0.1:' + порт(настройки) + '/штаб-онлайн';
    let запрос;
    try {
      запрос = http.get(адрес, { timeout: срокМс, headers: { [ЗАГОЛОВОК_КЛЮЧА_ШТАБА]: ключ } }, function (ответ) {
        let тело = '';
        ответ.setEncoding('utf8');
        ответ.on('data', function (кусок) { if (тело.length < 200000) тело += кусок; });
        ответ.on('end', function () {
          if (ответ.statusCode !== 200) {
            готово({ ошибка: 'сервер не отвечает как надо (код ' + ответ.statusCode + ')' });
            return;
          }
          try {
            готово({ сводка: JSON.parse(тело) });
          } catch (сбой) {
            готово({ ошибка: 'сервер не отвечает (ответ не понят)' });
          }
        });
      });
    } catch (сбой) {
      готово({ ошибка: 'сервер не отвечает' });
      return;
    }
    запрос.on('timeout', function () { запрос.destroy(); });
    запрос.on('error', function () { готово({ ошибка: 'сервер не отвечает' }); });
  });
}

