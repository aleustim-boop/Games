/*
  Поднимает номер ?v=N у общего файла (style.css, js/*.js) сразу во всех
  страницах корня, которые его подключают.

  Зачем. Правило проекта: правишь общий файл — поднимай ?v= у ВСЕХ страниц,
  которые его просят, иначе игроки со старым кэшем браузера не увидят
  изменений. Руками sed'ом по четырём файлам — долго и легко разъехаться
  (одна страница осталась на старом номере). Хуже: страницы часто несут
  чужие незакоммиченные правки (несколько исполнителей одновременно), и
  «поднять номер только в коммит» простым sed'ом по рабочей копии нельзя —
  туда же уедет и чужая правка. Ключ --в-индекс решает это: меняет номер
  только в версии, которая уходит в git-индекс (HEAD + сама смена номера),
  а рабочую копию поднимает как обычно, чужого не трогая.

      node штаб/поднять-номер.js <файл> [--показать] [--в-индекс] [--выровнять]

  <файл>      путь как в разметке: style.css, js/рейтинг-экран.js
  --показать  только печать, ничего не пишет ни на диск, ни в git
  --в-индекс  вдобавок кладёт в индекс git версию «HEAD + только смена
              номера» для каждой найденной страницы (см. ниже)
  --выровнять при разъезде номеров между страницами берёт максимум и
              поднимает все страницы на max+1 (вместо отказа)

  Коды выхода: 0 — сделано; 1 — нельзя (разъезд без --выровнять, файл
  никем не подключён, HEAD не совпал); 2 — ошибка самого git (hash-object,
  update-index).

  Скрытый ключ --корень <папка> — только для самопроверки (--проверить):
  подменяет корень проекта на временную папку, чтобы не трогать настоящий
  репозиторий. В обычной работе не указывается, корень — сам проект.

  Самопроверка: node штаб/поднять-номер.js --проверить
  Поднимает и проверяет всё на одноразовом git-репозитории во временной
  папке (fs.mkdtempSync в os.tmpdir()), которую сама же и удаляет в конце —
  это единственное допустимое удаление, и только своей временной папки.
*/

'use strict';

const fs = require('fs');
const path = require('path');
const os = require('os');
const { spawnSync } = require('child_process');

/* ---------------------------------------------------------------------------
   Поиск и разбор вхождений «файл?v=число» на страницах
--------------------------------------------------------------------------- */

/** Экранирует спецсимволы регэкспа — путь к файлу подставляется буквально. */
function экранироватьRegExp(строка) {
  return строка.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/* Паттерн ищет подстроку строго внутри пары одинаковых кавычек (двойных
   или одинарных) — так href="style.css?v=72" не путается со случайным
   совпадением где-то в тексте. \b здесь не годится: он не знает кириллицы
   (в путях бывает «js/рейтинг-экран.js»), поэтому не используем его вовсе.
   Группа 1 — кавычка, группа 2 — число версии. */
function построитьПаттерн(файл) {
  const экранированный = экранироватьRegExp(файл);
  return new RegExp('(["\'])' + экранированный + '\\?v=(\\d+)\\1', 'g');
}

/** Список *.html в корне (не рекурсивно), отсортированный для стабильного вывода. */
function найтиСтраницы(корень) {
  return fs.readdirSync(корень, { withFileTypes: true })
    .filter(function (запись) { return запись.isFile() && /\.html$/i.test(запись.name); })
    .map(function (запись) { return запись.name; })
    .sort();
}

/** Числа всех вхождений паттерна в тексте, по порядку появления. */
function числаВхождений(текст, файл) {
  const паттерн = построитьПаттерн(файл);
  const числа = [];
  let совпадение;
  while ((совпадение = паттерн.exec(текст))) {
    числа.push(Number(совпадение[2]));
  }
  return числа;
}

/** Заменяет во всех вхождениях число версии на новое, не трогая остальной текст. */
function заменитьЧисло(текст, файл, новоеЧисло) {
  const паттерн = построитьПаттерн(файл);
  return текст.replace(паттерн, function (совпадение, кавычка) {
    return кавычка + файл + '?v=' + новоеЧисло + кавычка;
  });
}

/* ---------------------------------------------------------------------------
   Вызовы git — всегда через spawnSync с доводами массивом, без shell:true,
   иначе кириллица в именах страниц (шашки.html и т.п.) и спецсимволы бьются
--------------------------------------------------------------------------- */

/** Содержимое страницы в HEAD. Нет файла в HEAD или git упал — ok:false. */
function получитьHEAD(корень, страница) {
  const результат = spawnSync('git', ['show', 'HEAD:' + страница], { cwd: корень, encoding: 'utf8' });
  if (результат.error) return { ok: false, причина: 'git не запустился: ' + результат.error.message };
  if (результат.status !== 0) {
    const сообщение = (результат.stderr || '').trim() || 'не нашёлся в HEAD';
    return { ok: false, причина: сообщение };
  }
  return { ok: true, текст: результат.stdout };
}

/** Пишет содержимое как блоб git, возвращает его хэш. */
function записатьBlob(корень, текст) {
  const результат = spawnSync('git', ['hash-object', '-w', '--stdin'], { cwd: корень, input: текст, encoding: 'utf8' });
  if (результат.error || результат.status !== 0) {
    const причина = (результат.stderr && результат.stderr.trim())
      || (результат.error && результат.error.message)
      || 'неизвестная ошибка hash-object';
    return { ok: false, причина: причина };
  }
  return { ok: true, хэш: результат.stdout.trim() };
}

/** Ставит блоб в индекс git на место страницы (режим обычного файла 100644). */
function поставитьВИндекс(корень, страница, хэш) {
  const результат = spawnSync('git', ['update-index', '--cacheinfo', '100644,' + хэш + ',' + страница], { cwd: корень, encoding: 'utf8' });
  if (результат.error || результат.status !== 0) {
    const причина = (результат.stderr && результат.stderr.trim())
      || (результат.error && результат.error.message)
      || 'неизвестная ошибка update-index';
    return { ok: false, причина: причина };
  }
  return { ok: true };
}

/* ---------------------------------------------------------------------------
   Главная работа
--------------------------------------------------------------------------- */

/** Итоговая строка о том, что поднято (или было бы поднято при --показать). */
function печатьИтога(файл, планы) {
  const текущиеУникальные = Array.from(new Set(планы.map(function (п) { return п.текущее; })));
  const новое = планы[0].новое;
  const имена = планы.map(function (п) { return п.страница; }).join(', ');
  if (текущиеУникальные.length === 1) {
    console.log(файл + ': ' + текущиеУникальные[0] + ' → ' + новое + ' на ' + планы.length + ' страницах: ' + имена);
  } else {
    const части = планы.map(function (п) { return п.страница + ' ' + п.текущее + '→' + новое; }).join(', ');
    console.log(файл + ': выровнено до ' + новое + ' — ' + части);
  }
}

/**
 * Делает всю работу для одного файла. Возвращает код выхода.
 * корень — абсолютный путь к папке с *.html (сам проект или временная
 * папка самопроверки).
 */
function поднятьНомер(корень, файл, флаги) {
  const страницы = найтиСтраницы(корень);

  const найденные = [];
  for (const страница of страницы) {
    const текст = fs.readFileSync(path.join(корень, страница), 'utf8');
    const числа = числаВхождений(текст, файл);
    if (числа.length) найденные.push({ страница: страница, текст: текст, числа: числа });
  }

  if (!найденные.length) {
    console.log(файл + ': файл никем не подключён');
    return 1;
  }

  for (const н of найденные) {
    console.log(н.страница + ': v=' + н.числа[0] + ', вхождений: ' + н.числа.length);
  }

  const всеЧисла = [];
  найденные.forEach(function (н) { н.числа.forEach(function (ч) { всеЧисла.push(ч); }); });
  const уникальные = Array.from(new Set(всеЧисла));
  const разъезд = уникальные.length > 1;

  if (разъезд && !флаги.выровнять) {
    const список = найденные.map(function (н) { return н.страница + ' ' + н.числа[0]; }).join(', ');
    console.log('разъезд: ' + список);
    return 1;
  }

  // Без разъезда максимум — это и есть единственное число; при выравнивании —
  // наибольшее среди разных. В обоих случаях новое значение — максимум + 1.
  const максимум = Math.max(...уникальные);
  const новое = максимум + 1;
  const планы = найденные.map(function (н) {
    return { страница: н.страница, текст: н.текст, текущее: н.числа[0], новое: новое };
  });

  if (флаги.показать) {
    печатьИтога(файл, планы);
    return 0;
  }

  if (флаги.вИндекс) {
    // Все проверки — до первой записи, чтобы не оставить половину страниц поднятыми.
    for (const п of планы) {
      const head = получитьHEAD(корень, п.страница);
      if (!head.ok) {
        console.log('HEAD:' + п.страница + ' — ' + head.причина);
        return 1;
      }
      const числаHead = числаВхождений(head.текст, файл);
      if (!числаHead.includes(п.текущее)) {
        console.log('HEAD:' + п.страница + ' не содержит ' + файл + '?v=' + п.текущее);
        return 1;
      }
      п.headТекст = head.текст;
    }
  }

  // Рабочие копии — обычной записью, чужие незакоммиченные правки не трогаем,
  // меняем только подстроку с номером версии.
  for (const п of планы) {
    const новыйТекст = заменитьЧисло(п.текст, файл, п.новое);
    fs.writeFileSync(path.join(корень, п.страница), новыйТекст, 'utf8');
  }

  if (флаги.вИндекс) {
    for (const п of планы) {
      const новыйHead = заменитьЧисло(п.headТекст, файл, п.новое);
      const блоб = записатьBlob(корень, новыйHead);
      if (!блоб.ok) {
        console.log('git hash-object: ' + блоб.причина);
        return 2;
      }
      const вИндексе = поставитьВИндекс(корень, п.страница, блоб.хэш);
      if (!вИндексе.ok) {
        console.log('git update-index: ' + вИндексе.причина);
        return 2;
      }
    }
  }

  печатьИтога(файл, планы);
  return 0;
}

/* ---------------------------------------------------------------------------
   Самопроверка — временный git-репозиторий, никакого касания настоящего проекта
--------------------------------------------------------------------------- */

/** Выполняет git-команду во временном репозитории, кидает исключение при ошибке. */
function выполнитьГит(доводы, папка) {
  const результат = spawnSync('git', доводы, { cwd: папка, encoding: 'utf8' });
  if (результат.status !== 0) {
    throw new Error('git ' + доводы.join(' ') + ' упал: ' + (результат.stderr || (результат.error && результат.error.message)));
  }
  return результат.stdout;
}

function самопроверка() {
  let проверок = 0;
  let провалов = 0;
  function проверить(имя, условие) {
    проверок += 1;
    if (!условие) {
      провалов += 1;
      console.log('ПЛОХО — ' + имя);
    }
  }

  const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'podnyat-nomer-'));
  try {
    выполнитьГит(['init'], врем);
    // autocrlf выключаем: на Windows он мог бы подменить переводы строк
    // в блобах, и наши текстовые сравнения перестали бы совпадать.
    выполнитьГит(['config', 'core.autocrlf', 'false'], врем);

    const шаблон = '<!doctype html>\n<html><head>\n'
      + '<link rel="stylesheet" href="style.css?v=5">\n'
      + '</head><body>\n<script src="js/игра.js?v=2"></script>\n</body></html>\n';
    fs.writeFileSync(path.join(врем, 'а.html'), шаблон, 'utf8');
    fs.writeFileSync(path.join(врем, 'б.html'), шаблон, 'utf8');

    выполнитьГит(['add', 'а.html', 'б.html'], врем);
    выполнитьГит(['-c', 'user.name=Штаб', '-c', 'user.email=shtab@example.com',
      'commit', '-m', 'исходные страницы для самопроверки'], врем);

    // Посторонняя правка в рабочей копии а.html — не коммитим её.
    fs.appendFileSync(path.join(врем, 'а.html'), '<!-- посторонняя правка -->\n', 'utf8');

    const путьКПрограмме = __filename;

    // --- (1)+(2)+(3): --в-индекс поднимает style.css, не трогая js/игра.js
    //     и не унося постороннюю правку в индекс.
    const запуск1 = spawnSync(process.execPath,
      [путьКПрограмме, 'style.css', '--в-индекс', '--корень', врем], { encoding: 'utf8' });
    проверить('--в-индекс завершился кодом 0 (получили ' + запуск1.status + ')', запуск1.status === 0);

    const аПосле1 = fs.readFileSync(path.join(врем, 'а.html'), 'utf8');
    const бПосле1 = fs.readFileSync(path.join(врем, 'б.html'), 'utf8');
    проверить('а.html поднят до style.css?v=6', аПосле1.includes('style.css?v=6'));
    проверить('б.html поднят до style.css?v=6', бПосле1.includes('style.css?v=6'));
    проверить('js/игра.js?v=2 в а.html не тронут', аПосле1.includes('js/игра.js?v=2'));
    проверить('js/игра.js?v=2 в б.html не тронут', бПосле1.includes('js/игра.js?v=2'));

    const вИндексе = выполнитьГит(['diff', '--cached'], врем);
    проверить('git diff --cached содержит ?v=6', вИндексе.includes('v=6'));
    проверить('git diff --cached не содержит постороннюю правку', !вИндексе.includes('посторонняя правка'));

    // Смотрим только на добавленные/удалённые строки diff (не на контекстные —
    // в контексте естественно попадается «js/игра.js?v=2», это не изменение).
    const вРабочейКопии = выполнитьГит(['diff'], врем);
    const изменённыеСтрокиРабочей = вРабочейКопии.split('\n').filter(function (строка) {
      return (строка.startsWith('+') && !строка.startsWith('+++'))
        || (строка.startsWith('-') && !строка.startsWith('---'));
    });
    проверить('git diff содержит постороннюю правку', изменённыеСтрокиРабочей.some(function (с) { return с.includes('посторонняя правка'); }));
    проверить('git diff не меняет номер версии (нет строк ?v= среди изменённых)', !изменённыеСтрокиРабочей.some(function (с) { return с.includes('?v='); }));

    // --- (4): разъезд номеров — подменяем б.html на v=4.
    const бДоРазъезда = fs.readFileSync(path.join(врем, 'б.html'), 'utf8');
    fs.writeFileSync(path.join(врем, 'б.html'), бДоРазъезда.replace('style.css?v=6', 'style.css?v=4'), 'utf8');
    const снимокА = fs.readFileSync(path.join(врем, 'а.html'), 'utf8');
    const снимокБ = fs.readFileSync(path.join(врем, 'б.html'), 'utf8');

    const запускРазъезд = spawnSync(process.execPath,
      [путьКПрограмме, 'style.css', '--корень', врем], { encoding: 'utf8' });
    проверить('разъезд без --выровнять даёт код 1 (получили ' + запускРазъезд.status + ')', запускРазъезд.status === 1);
    проверить('разъезд без --выровнять не меняет а.html', fs.readFileSync(path.join(врем, 'а.html'), 'utf8') === снимокА);
    проверить('разъезд без --выровнять не меняет б.html', fs.readFileSync(path.join(врем, 'б.html'), 'utf8') === снимокБ);

    const запускВыровнять = spawnSync(process.execPath,
      [путьКПрограмме, 'style.css', '--выровнять', '--корень', врем], { encoding: 'utf8' });
    проверить('--выровнять завершился кодом 0 (получили ' + запускВыровнять.status + ')', запускВыровнять.status === 0);
    проверить('--выровнять поднял а.html до v=7 (max 6 + 1)', fs.readFileSync(path.join(врем, 'а.html'), 'utf8').includes('style.css?v=7'));
    проверить('--выровнять поднял б.html до v=7 (max 6 + 1)', fs.readFileSync(path.join(врем, 'б.html'), 'utf8').includes('style.css?v=7'));

    // --- (5): --показать ничего не пишет.
    const доПоказать = fs.readFileSync(path.join(врем, 'а.html'), 'utf8');
    spawnSync(process.execPath, [путьКПрограмме, 'style.css', '--показать', '--корень', врем], { encoding: 'utf8' });
    проверить('--показать не меняет а.html', fs.readFileSync(path.join(врем, 'а.html'), 'utf8') === доПоказать);
  } finally {
    fs.rmSync(врем, { recursive: true });
  }

  console.log('Итого проверок: ' + проверок + ', провалов: ' + провалов);
  return провалов ? 1 : 0;
}

/* ---------------------------------------------------------------------------
   Разбор командной строки
--------------------------------------------------------------------------- */

if (process.argv.includes('--проверить')) {
  process.exit(самопроверка());
}

const доводы = process.argv.slice(2);
let файл = null;
let корень = path.join(__dirname, '..');
const флаги = { показать: false, вИндекс: false, выровнять: false };

for (let i = 0; i < доводы.length; i += 1) {
  const довод = доводы[i];
  if (довод === '--показать') флаги.показать = true;
  else if (довод === '--в-индекс') флаги.вИндекс = true;
  else if (довод === '--выровнять') флаги.выровнять = true;
  else if (довод === '--корень') { корень = доводы[i + 1]; i += 1; }
  else if (!довод.startsWith('--') && файл === null) файл = довод;
}

if (!файл) {
  console.log('нужен довод — файл как в разметке, например style.css или js/рейтинг-экран.js');
  process.exit(1);
}

process.exit(поднятьНомер(корень, файл, флаги));
