// Мост дашборда штаба: держит быстрый туннель cloudflared к 127.0.0.1:8791 и
// сообщает серверу igra новый адрес туннеля, чтобы https://igra.medart.com.ua/shtab/
// всегда вёл на дашборд.
// Адрес туннеля меняется при каждом его перезапуске — отсюда и мост.
//
// Запуск:
//   node штаб/мост-дашборда.js                  — уходит в фон (отвязанная копия), пишет в штаб/мост-дашборда.log
//   node штаб/мост-дашборда.js --передний-план  — работает прямо здесь (так работает и фоновая копия)
//   node штаб/мост-дашборда.js --остановить     — снимает мост и его cloudflared по номерам из pid-файлов
'use strict';

const fs = require('fs');
const path = require('path');
const { spawn } = require('child_process');

const ПУТЬ_CLOUDFLARED = 'C:\\Program Files (x86)\\cloudflared\\cloudflared.exe';
const ПОРТ_ДАШБОРДА = 8791;
const ID_МАШИНЫ_IGRA = '5dd873f7-48f9-4fc4-b6f0-3dc18610f400';
const ПАУЗА_ПОСЛЕ_СМЕРТИ_МС = 10000;
const ПАУЗА_ПОВТОРА_МС = 30000;

// Хост подставляется в bash и в конфиг nginx — других символов быть не может.
const МЕРКА_ХОСТА = /^[a-z0-9-]+\.trycloudflare\.com$/;

const КОНЕЦ_ТЕКСТА = 'SHTAB_CONF_END';

// Достаёт адрес туннеля из вывода cloudflared или возвращает null.
// Берём только то, что стоит после «https://», и только если оно целиком
// проходит мерку: «a.trycloudflare.com.evil.com» или «evil.com/x.trycloudflare.com» не пройдут.
function найтиАдрес(текст) {
  const найденные = String(текст || '').matchAll(/https:\/\/([^\s\/|"'<>]+)/g);
  for (const совпадение of найденные) {
    const хост = совпадение[1];
    if (!МЕРКА_ХОСТА.test(хост)) continue; // МЕРКА-В-НАЙТИАДРЕС
    if (хост === 'api.trycloudflare.com') continue; // это служебный адрес самого cloudflare
    return хост;
  }
  return null;
}

function проверитьХост(хост) {
  if (typeof хост !== 'string' || !МЕРКА_ХОСТА.test(хост)) {
    throw new Error('недопустимый адрес туннеля');
  }
}

// Общая часть скриптов: пути, копии «на случай отката» и сам откат.
// Имена переменных bash — латиницей.
function началоСкрипта() {
  return [
    'set -u',
    'ADR=/etc/nginx/shtab-adres.conf',
    'LOC=/etc/nginx/shtab-location.conf',
    'IGRA=/etc/nginx/sites-available/igra',
    'BACKUP=/tmp/shtab-rezerv',
    'mkdir -p "$BACKUP"',
    'rm -f "$BACKUP"/*',
    'for f in "$ADR" "$LOC" "$IGRA"; do',
    '  if [ -e "$f" ]; then cp -P "$f" "$BACKUP/$(basename "$f").bak"; else : > "$BACKUP/$(basename "$f").net"; fi',
    'done',
    'restore() {',
    '  for f in "$ADR" "$LOC" "$IGRA"; do',
    '    b="$BACKUP/$(basename "$f")"',
    '    if [ -e "$b.bak" ]; then cp -P "$b.bak" "$f"; else rm -f "$f"; fi',
    '  done',
    '}',
  ].join('\n');
}

// Конец скриптов: проверка nginx, откат при провале, мягкая перезагрузка при успехе.
function конецСкрипта() {
  return [
    'if ! nginx -t; then',
    '  echo "nginx -t не прошёл, возвращаю прежние файлы" >&2',
    '  restore',
    '  exit 1',
    'fi',
    'systemctl reload nginx',
  ].join('\n');
}

function строкаАдреса(хост) {
  return 'printf \'%s\\n\' \'set $shtab_host "' + хост + '";\' > "$ADR"';
}

// Защита вставки: строка «listen 443 ssl» в конфиге игры должна быть ровно одна,
// иначе непонятно, куда вставлять, — тогда ничего не трогаем.
function вставкаИнклюда() {
  return [
    'COUNT=$(grep -c \'^[[:space:]]*listen 443 ssl\' "$IGRA")',
    'if [ "$COUNT" != "1" ]; then',
    '  echo "в $IGRA строк listen 443 ssl: $COUNT, а нужна ровно одна; ничего не менял" >&2',
    '  exit 1',
    'fi',
  ].join('\n');
}

function вставитьИнклюд() {
  return [
    'if ! grep -q \'include /etc/nginx/shtab-location.conf;\' "$IGRA"; then',
    '  sed -i \'/^[[:space:]]*listen 443 ssl/i\\    include /etc/nginx/shtab-location.conf;\' "$IGRA"',
    'fi',
  ].join('\n');
}

// Полная установка: адрес, кусок конфига, одна строка include в конфиге игры, проверка, reload.
function скриптУстановки(хост, текстКонфига) {
  проверитьХост(хост);
  const конфиг = String(текстКонфига || '');
  if (!конфиг.trim()) throw new Error('пустой конфиг nginx');
  if (конфиг.includes(КОНЕЦ_ТЕКСТА)) throw new Error('в конфиге есть служебная метка конца');
  return [
    началоСкрипта(),
    вставкаИнклюда(),
    строкаАдреса(хост),
    'cat > "$LOC" <<\'' + КОНЕЦ_ТЕКСТА + '\'',
    конфиг.replace(/\n$/, ''),
    КОНЕЦ_ТЕКСТА,
    вставитьИнклюд(),
    конецСкрипта(),
    '',
  ].join('\n');
}

// Только новый адрес: переписать одну строку, проверить, перезагрузить.
function скриптАдреса(хост) {
  проверитьХост(хост);
  return [
    началоСкрипта(),
    строкаАдреса(хост),
    конецСкрипта(),
    '',
  ].join('\n');
}

// Время в журнале — местное, как у сторожа.
function метка() {
  return new Date().toLocaleString('ru-RU');
}

// Это именно наш мост, а не чужая программа, которой Windows отдал тот же номер?
// Принимает строку запуска процесса (или null, если узнать не удалось — тогда не мост).
function этоМост(строка) {
  return typeof строка === 'string' && /(^|[\s"'\\/])мост-дашборда\.js(?=["'\s]|$)/i.test(строка);
}

// Это cloudflared именно нашего туннеля (к дашборду на 8791), а не чужой
// (на машине работает ещё один, на localhost:8765, — его трогать нельзя).
function этоНашТуннель(строка) {
  if (typeof строка !== 'string') return false;
  const этоCloudflared = /(^|[\s"'\\/])cloudflared(\.exe)?(?=["'\s]|$)/i.test(строка);
  return этоCloudflared && /127\.0\.0\.1:8791(?![0-9])/.test(строка);
}

// Разбор флагов командной строки (аргументы без node и имени скрипта).
function разобратьФлаги(аргументы) {
  const список = Array.isArray(аргументы) ? аргументы : [];
  return {
    передПлан: список.includes('--передний-план'),
    остановить: список.includes('--остановить'),
  };
}

function процессЖив(номер) {
  try {
    process.kill(номер, 0);
    return true;
  } catch (_) {
    return false;
  }
}

function прочитатьНомер(файл) {
  try {
    const номер = Number(fs.readFileSync(файл, 'utf8').trim());
    return Number.isInteger(номер) && номер > 0 ? номер : null;
  } catch (_) {
    return null;
  }
}

// Стирает pid-файл, только если в нём ещё наш номер: файл мог переписать более новый запуск.
function убратьPidФайл(файл, номер) {
  try {
    if (прочитатьНомер(файл) === номер) fs.unlinkSync(файл);
  } catch (_) { /* уже нет */ }
}

// Запускает мост. Все внешние зависимости можно подменить доводами (для проверки без сети):
//   запуститьПроцесс(путь, аргументы) → дочерний процесс; выполнитьСкрипт(id, текст, настройки);
//   пауза(мс) → обещание; журнал(строка); конфиг — текст shtab.conf.
// Возвращает { готово: обещание на конец работы, остановить() }.
function запустить(доводы) {
  const д = доводы || {};
  const запуститьПроцесс = д.запуститьПроцесс || spawn;
  const выполнить = д.выполнитьСкрипт;
  const пауза = д.пауза || ((мс) => new Promise((готово) => setTimeout(готово, мс)));
  const журнал = д.журнал || (() => {});
  const текстКонфига = д.конфиг;

  let стоп = false;
  let процесс = null;
  let текущийХост = null;
  let установлено = false;

  async function отправить(хост) {
    // Повторяем, пока не выйдет — но если за это время пришёл другой адрес, этот уже не нужен.
    while (!стоп && текущийХост === хост) {
      try {
        const полная = !установлено;
        const скрипт = полная ? скриптУстановки(хост, текстКонфига) : скриптАдреса(хост);
        журнал((полная ? 'отправляю установку' : 'отправляю новый адрес') + ': ' + хост);
        const итог = await выполнить(ID_МАШИНЫ_IGRA, скрипт, { срокМс: 90000 });
        if (итог && итог.код && Number(итог.код) !== 0) {
          throw new Error('скрипт на igra вернул код ' + итог.код + (итог.ошибки ? ': ' + String(итог.ошибки).slice(0, 300) : ''));
        }
        if (полная) установлено = true;
        журнал('готово: ' + хост);
        return;
      } catch (ошибка) {
        журнал('не вышло отправить (' + ошибка.message + '), повтор через ' + ПАУЗА_ПОВТОРА_МС / 1000 + ' с');
        await пауза(ПАУЗА_ПОВТОРА_МС);
      }
    }
  }

  const отправки = [];

  function наВывод(кусок) {
    const хост = найтиАдрес(String(кусок));
    if (!хост || хост === текущийХост) return;
    текущийХост = хост;
    журнал('новый адрес туннеля: ' + хост);
    отправки.push(отправить(хост));
  }

  async function цикл() {
    while (!стоп) {
      журнал('запускаю cloudflared');
      const дочерний = запуститьПроцесс(ПУТЬ_CLOUDFLARED, ['tunnel', '--url', 'http://127.0.0.1:' + ПОРТ_ДАШБОРДА]);
      процесс = дочерний;
      дочерний.stdout && дочерний.stdout.on('data', наВывод);
      дочерний.stderr && дочерний.stderr.on('data', наВывод);
      await new Promise((готово) => {
        дочерний.once('error', (о) => { журнал('cloudflared: ошибка ' + о.message); готово(); });
        дочерний.once('close', () => готово());
      });
      процесс = null;
      if (стоп) break;
      журнал('cloudflared остановился, жду ' + ПАУЗА_ПОСЛЕ_СМЕРТИ_МС / 1000 + ' с');
      await пауза(ПАУЗА_ПОСЛЕ_СМЕРТИ_МС);
    }
    await Promise.all(отправки);
  }

  return {
    готово: цикл(),
    остановить() {
      стоп = true;
      if (процесс && typeof процесс.kill === 'function') {
        try { процесс.kill(); } catch (_) { /* уже завершился */ }
      }
    },
  };
}

const ПАПКА = __dirname;
const ФАЙЛ_ЖУРНАЛА = path.join(ПАПКА, 'мост-дашборда.log');
const ФАЙЛ_НОМЕРА = path.join(ПАПКА, 'мост-дашборда.pid');
const ФАЙЛ_НОМЕРА_ТУННЕЛЯ = path.join(ПАПКА, 'мост-дашборда-туннель.pid');

// Строка запуска процесса по номеру. Подключаем лениво: копия файла во временной папке
// (для проверки) грузится без соседних файлов штаба.
function строкаЗапускаПроцесса(номер) {
  return require('./перезапуск-дашборда.js').строкаЗапуска(номер);
}

// Журнал: в файл — всегда, в консоль — только если это терминал. У фоновой копии
// stdout и есть файл журнала, иначе каждая строка встала бы дважды.
function записатьВЖурнал(строка) {
  const полная = '[' + метка() + '] ' + строка;
  if (process.stdout.isTTY) console.log(полная);
  try { fs.appendFileSync(ФАЙЛ_ЖУРНАЛА, полная + '\n'); } catch (_) { /* журнал не важнее работы */ }
}

// Поднимает отвязанную копию себя с флагом --передний-план и завершается.
function уйтиВФон() {
  const поток = fs.openSync(ФАЙЛ_ЖУРНАЛА, 'a');
  const дитя = spawn(process.execPath, [__filename, '--передний-план'],
    { cwd: path.join(ПАПКА, '..'), detached: true, windowsHide: true, stdio: ['ignore', поток, поток] });
  дитя.unref();
  console.log('мост дашборда поднят в фоне, номер процесса ' + дитя.pid + ', журнал: штаб/мост-дашборда.log');
}

// Снимает мост и его cloudflared по номерам из pid-файлов, сверив строку запуска.
// Чужие процессы (в том числе cloudflared на 8765) не трогает.
function остановитьМост() {
  const снять = (файл, мерка, имя) => {
    const номер = прочитатьНомер(файл);
    if (!номер) { console.log(имя + ': pid-файла нет или в нём мусор — нечего снимать'); return; }
    if (!процессЖив(номер)) { console.log(имя + ' (номер ' + номер + ') уже не работает'); убратьPidФайл(файл, номер); return; }
    if (!мерка(строкаЗапускаПроцесса(номер))) { console.log(имя + ': номер ' + номер + ' — не наш процесс, не трогаю'); return; }
    try {
      process.kill(номер);
      console.log(имя + ' снят, номер ' + номер);
      убратьPidФайл(файл, номер);
    } catch (о) {
      console.log(имя + ': не удалось снять номер ' + номер + ' (' + о.message + ')');
    }
  };
  // Сначала мост (чтобы не перезапустил туннель), потом туннель.
  снять(ФАЙЛ_НОМЕРА, этоМост, 'мост');
  снять(ФАЙЛ_НОМЕРА_ТУННЕЛЯ, этоНашТуннель, 'туннель cloudflared');
}

function работатьВПереднемПлане() {
  const старыйНомер = прочитатьНомер(ФАЙЛ_НОМЕРА);
  if (старыйНомер && старыйНомер !== process.pid && процессЖив(старыйНомер) && этоМост(строкаЗапускаПроцесса(старыйНомер))) {
    записатьВЖурнал('мост уже запущен (номер процесса ' + старыйНомер + ') — этот экземпляр завершается');
    return;
  }
  const конфиг = fs.readFileSync(path.join(ПАПКА, '..', 'server', 'nginx', 'shtab.conf'), 'utf8');
  const { выполнитьСкрипт } = require('./вм.js');
  fs.writeFileSync(ФАЙЛ_НОМЕРА, String(process.pid));

  // Номер своего cloudflared пишем при каждом запуске туннеля — для --остановить.
  let номерТуннеля = null;
  const запуститьТуннель = (путь, аргументы) => {
    const дочерний = spawn(путь, аргументы, { windowsHide: true });
    if (дочерний.pid) {
      номерТуннеля = дочерний.pid;
      try { fs.writeFileSync(ФАЙЛ_НОМЕРА_ТУННЕЛЯ, String(номерТуннеля)); } catch (_) { /* не критично */ }
    }
    return дочерний;
  };

  const мост = запустить({ запуститьПроцесс: запуститьТуннель, выполнитьСкрипт, журнал: записатьВЖурнал, конфиг });
  let выходим = false;
  const завершить = () => {
    if (выходим) return;
    выходим = true;
    мост.остановить(); // гасим свой cloudflared по его номеру, а не по имени
    убратьPidФайл(ФАЙЛ_НОМЕРА, process.pid);
    if (номерТуннеля) убратьPidФайл(ФАЙЛ_НОМЕРА_ТУННЕЛЯ, номерТуннеля);
  };
  process.on('SIGINT', () => { завершить(); process.exit(0); });
  process.on('SIGTERM', () => { завершить(); process.exit(0); });
  process.on('exit', завершить);
  записатьВЖурнал('мост запущен, номер процесса ' + process.pid);
}

function главная() {
  const флаги = разобратьФлаги(process.argv.slice(2));
  if (флаги.остановить) остановитьМост();
  else if (флаги.передПлан) работатьВПереднемПлане();
  else уйтиВФон();
}

if (require.main === module) {
  главная();
}

module.exports = { найтиАдрес, скриптУстановки, скриптАдреса, запустить, этоМост, этоНашТуннель, разобратьФлаги };
