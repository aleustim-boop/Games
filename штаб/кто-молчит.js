/*
  Сторож простоя: кто из исполнителей давно ничего не писал.

      node штаб/кто-молчит.js        (порог — полчаса)
      node штаб/кто-молчит.js 60     (порог — час)

  Зачем. Владелец написал: «разберись, почему молчат исполнители, и сделай
  так, чтобы этого больше не было». Разбор показал, что молчат не они:
  они заканчивают и ждут задачу, а штаб не возвращается к освободившемуся,
  потому что рядом идут десять других дел. Один исполнитель простоял
  десять часов, и никто этого не заметил, пока не спросил владелец.

  ЧЕМ МЕРЯЕМ — читать обязательно, иначе числу нельзя верить.

  У каждого запущенного исполнителя есть файл записей, и он растёт, пока тот
  работает. Отсюда главный признак: **сколько минут в этот файл ничего не
  писали**. Содержимое не читается ни строчкой — файлы бывают по десять
  мегабайт; спрашивается только карточка файла у системы.

  Отдельно скажу про «рост файла», о котором меня спросили. Мерить рост
  отдельно от времени записи бессмысленно: **файл растёт только когда в него
  пишут, а запись сама обновляет время последней правки**. Это один и тот же
  сигнал, а не два. Поэтому я меряю тишину по времени, а не выдумываю вторую
  мерку, которая на деле показывает то же самое.

  А вот что вправду добавляет знания — **обычный ритм этого исполнителя**.
  Турнир на две тысячи партий шёл шесть часов, и всё это время исполнитель
  писал редко, но писал. Поэтому программа помнит, когда у каждого менялся
  размер файла (штаб/следы-исполнителей.json), и знает его самую долгую
  прежнюю паузу. Если человек весь день пишет раз в двадцать минут, тишина
  в двадцать пять минут для него обычна, и кричать о ней не надо.

  ЧЕГО ЭТА ПРОГРАММА НЕ УМЕЕТ — говорю прямо, чтобы не верили лишнему.
  Отличить «исполнитель встал» от «исполнитель ждёт долгую команду» по файлам
  нельзя: и в том, и в другом случае в файл ничего не пишется. Поэтому вывод
  здесь всегда «молчит столько-то — посмотрите», а не «встал». Решает человек.

  Расписания у сторожа нет нарочно: он срабатывает, только когда его зовут.
*/

'use strict';

const fs = require('fs');
const path = require('path');
const живость = require('./живость.js');

const ФАЙЛ_РАБОТ = path.join(__dirname, 'в-работе.json');
const ФАЙЛ_СЛЕДОВ = path.join(__dirname, 'следы-исполнителей.json');

const ПОРОГ_ПО_УМОЛЧАНИЮ = 30;   // минут тишины, после которых спрашиваем
const РЕЖЕ_ЧЕМ_РАЗ_В = 60000;    // не переписываем следы чаще раза в минуту

function минут(отДаты, доМиллисекунд) {
  return Math.max(0, Math.round((доМиллисекунд - отДаты.getTime()) / 60000));
}

/** «7 мин», «2 ч 10 мин», «3 дн» — по-человечески. */
function словами(мин) {
  return живость.словамиДлительность(мин);
}

/* ---------------------------------------------------------------------------
   Следы: когда у кого менялся размер файла
--------------------------------------------------------------------------- */

function прочитатьСледы() {
  try {
    const данные = JSON.parse(fs.readFileSync(ФАЙЛ_СЛЕДОВ, 'utf8'));
    return данные && данные.следы ? данные.следы : {};
  } catch (ошибка) {
    return {};
  }
}

function записатьСледы(следы) {
  try {
    const было = fs.existsSync(ФАЙЛ_СЛЕДОВ) ? fs.statSync(ФАЙЛ_СЛЕДОВ).mtime.getTime() : 0;
    if (Date.now() - было < РЕЖЕ_ЧЕМ_РАЗ_В) return; // не дёргаем диск попусту
    fs.writeFileSync(ФАЙЛ_СЛЕДОВ, JSON.stringify({
      'что это': 'когда у каждого исполнителя менялся размер файла записей. По этим отметкам сторож знает обычный ритм работы и не поднимает тревогу там, где человек просто пишет редко. Ведёт программа штаб/кто-молчит.js, руками сюда не надо.',
      следы: следы
    }, null, 2) + '\n', 'utf8');
  } catch (ошибка) {
    /* следы — приятная мелочь: не записались, значит судим по одной тишине */
  }
}

/**
 * Самая долгая прежняя пауза между записями — по отметкам.
 * Меньше двух отметок — сказать нечего, честный null.
 */
function обычнаяПауза(отметки) {
  if (!Array.isArray(отметки) || отметки.length < 3) return null;
  let самая = 0;
  for (let i = 1; i < отметки.length; i++) {
    const разрыв = Math.round((new Date(отметки[i]) - new Date(отметки[i - 1])) / 60000);
    if (разрыв > самая) самая = разрыв;
  }
  return самая;
}

/* ---------------------------------------------------------------------------
   Главный сбор
--------------------------------------------------------------------------- */

/**
 * Этот след — от прежнего запуска, а не от нынешней работы?
 *
 * Отвечаем «да», только когда знаем время начала работы и файл записей
 * не менялся после него. Времени начала нет — молчим: гадать нельзя,
 * иначе живой исполнитель попадёт под тот же признак и настоящее
 * молчание останется незамеченным.
 *
 * Небольшой запас в минуту — на разницу часов файла и записи о работе.
 */
function следНеОтЭтойРаботы(запись, работа) {
  if (!работа || !работа.начато) return false;
  // Разбор общий с штаб/в-работе.js: «2026-09-10 23:50», старое «23:50» и ISO.
  // Раньше здесь стояло new Date(работа.начато), а оно «23:50» не понимает —
  // и признак вчерашнего следа молча не работал для записей штаба вовсе.
  const начато = живость.разобратьНачато(работа.начато);
  if (!начато) return false;
  const изменён = new Date(запись.изменён).getTime();
  return изменён + ЗАПАС_ЧАСОВ < начато.getTime();
}

/* Запас на разнобой часов: файл и запись о работе пишут разные программы. */
const ЗАПАС_ЧАСОВ = 60 * 1000;

function прочитатьРаботы() {
  try {
    const данные = JSON.parse(fs.readFileSync(ФАЙЛ_РАБОТ, 'utf8'));
    return Array.isArray(данные.работы) ? данные.работы : [];
  } catch (ошибка) {
    return null;
  }
}

/**
 * Кто молчит дольше порога.
 * запоминать = false — только смотрим, файл следов не трогаем (так зовёт
 * дашборд, который спрашивает состояние по многу раз в минуту).
 */
function собрать(порогМинут, запоминать, подделка) {
  const порог = Number(порогМинут) > 0 ? Number(порогМинут) : ПОРОГ_ПО_УМОЛЧАНИЮ;
  const сейчас = Date.now();

  /* Третий довод — только для проверки: подделанные записи и работы.
     Своих настоящих она при этом не трогает вовсе, и наоборот — живые
     данные штаба, которые правятся прямо во время работы, не могут
     покрасить проверку в красное. */
  const сведения = подделка && подделка.записи
    ? { найдена: true, записи: подделка.записи }
    : живость.записиИсполнителей();
  const работы = подделка && подделка.работы ? подделка.работы : прочитатьРаботы();

  if (работы === null) {
    return { порог: порог, беда: 'файл штаб/в-работе.json не читается — сторожить некого', строки: [], молчат: 0 };
  }
  if (!работы.length) {
    return { порог: порог, беда: 'в списке работ пусто: сейчас никто ничего не делает', строки: [], молчат: 0 };
  }
  if (!сведения.найдена) {
    return { порог: порог, беда: сведения.беда, строки: [], молчат: 0 };
  }

  const следы = прочитатьСледы();
  let следыМенялись = false;
  const строки = [];

  for (const работа of работы) {
    const строка = {
      кто: работа.кто || '(без имени)',
      что: работа.что || '',
      задача: работа.задача || null,
      тишина: null,
      размер: null,
      обычнаяПауза: null,
      состояние: 'связь не настроена',
      слова: 'у этой работы не заполнено поле «задача» — какой файл записей её, я не знаю'
    };

    if (строка.задача) {
      const ключ = String(строка.задача).toLowerCase();
      const запись = сведения.записи.find(function (з) {
        const имя = з.имя.toLowerCase();
        return имя.startsWith(ключ) || ключ.startsWith(имя);
      });

      if (!запись) {
        строка.состояние = 'нет файла';
        строка.слова = 'файла записей с таким номером нет — исполнителя, похоже, уже нет вовсе';
      } else if (следНеОтЭтойРаботы(запись, работа)) {
        /* СЛЕД ВЧЕРАШНЕГО. Сторож однажды написал «оформитель молчит
           11 ч 26 мин» ровно в то время, когда оформитель работал: он
           смотрел на файл записей ПРОШЛОГО оформителя, давно завершённого.
           Мёртвый файл не растёт, и со стороны это неотличимо от молчания
           живого — поэтому тревога превращалась в фоновый шум, а заводили
           сторожа ровно затем, чтобы не проглядеть настоящее молчание.

           Признак, а не срок: файл не менялся НИ РАЗУ с тех пор, как эту
           работу поставили. Значит по ней исполнитель не написал ни строчки,
           а найденный файл — чужой, от прежнего запуска. Живой исполнитель,
           который ждёт долгую команду, сюда не попадёт никогда: его файл
           менялся хотя бы раз после начала работы. */
        строка.состояние = 'след устарел';
        строка.тишина = минут(запись.изменён, сейчас);
        строка.слова = 'номер задачи ведёт на файл прежнего запуска: он не менялся с тех пор, ' +
          'как работу поставили. Это не молчание — обновите номер задачи или уберите работу из списка';
      } else {
        строка.тишина = минут(запись.изменён, сейчас);
        строка.размер = запись.размер;

        // Отметка о смене размера — по ней потом виден обычный ритм.
        const след = следы[запись.имя] || { размер: -1, отметки: [] };
        if (след.размер !== запись.размер) {
          след.размер = запись.размер;
          след.отметки = (след.отметки || []).concat([new Date(запись.изменён).toISOString()]).slice(-30);
          следы[запись.имя] = след;
          следыМенялись = true;
        }
        строка.обычнаяПауза = обычнаяПауза(след.отметки);

        if (запись.размер === 0) {
          строка.состояние = 'не начал';
          строка.слова = 'файл записей пуст: исполнителя запустили ' + словами(строка.тишина)
            + ' назад, но он не написал ни строчки';
        } else if (строка.тишина < порог) {
          строка.состояние = 'пишет';
          строка.слова = строка.тишина <= 2 ? 'пишет прямо сейчас' : 'последняя запись ' + словами(строка.тишина) + ' назад';
        } else if (строка.обычнаяПауза !== null && строка.тишина <= строка.обычнаяПауза) {
          // У него и раньше бывали такие паузы — значит это его обычный ритм.
          строка.состояние = 'редко пишет';
          строка.слова = 'молчит ' + словами(строка.тишина)
            + ', но у него и раньше бывали паузы до ' + словами(строка.обычнаяПауза) + ' — похоже, так работает';
        } else {
          строка.состояние = 'молчит';
          строка.слова = 'молчит ' + словами(строка.тишина)
            + (строка.обычнаяПауза !== null ? ', а обычно пишет хотя бы раз в ' + словами(строка.обычнаяПауза) : '');
        }
      }
    }

    строки.push(строка);
  }

  if (запоминать && следыМенялись) записатьСледы(следы);

  // Сортируем по тишине: кто дольше всех молчит — первым.
  строки.sort(function (а, б) { return (б.тишина || 0) - (а.тишина || 0); });

  const молчат = строки.filter(function (с) {
    return с.состояние === 'молчит' || с.состояние === 'нет файла' || с.состояние === 'не начал';
  });

  return {
    порог: порог,
    беда: null,
    строки: строки,
    молчат: молчат.length,
    самаяДолгаяТишина: строки.length ? строки[0].тишина : null
  };
}

/* ---------------------------------------------------------------------------
   Как это читается людьми
--------------------------------------------------------------------------- */

/** Одна строка для конца отчёта: её печатает и штаб/в-работе.js. */
function однойСтрокой(итог) {
  if (итог.беда) return 'сторож простоя: ' + итог.беда;
  if (!итог.молчат) {
    return 'сторож простоя: все ' + итог.строки.length + ' пишут (порог ' + итог.порог + ' мин)';
  }
  const кто = итог.строки
    .filter(function (с) { return с.состояние === 'молчит' || с.состояние === 'нет файла' || с.состояние === 'не начал'; })
    .map(function (с) { return с.кто + ' — ' + (с.тишина === null ? 'нет файла' : словами(с.тишина)); });
  return 'МОЛЧАТ (' + итог.молчат + '): ' + кто.join('; ') + '. Это не их вина — им нечего делать, дайте задачу.';
}

/** Подробная печать для команды в терминале. */
function напечатать(итог) {
  if (итог.беда) {
    console.log('сторож простоя: ' + итог.беда);
    return;
  }

  console.log('порог тишины: ' + итог.порог + ' мин. Работ в списке: ' + итог.строки.length);
  console.log('');
  for (const с of итог.строки) {
    const метка = {
      'пишет': '  ок  ', 'редко пишет': ' ждём ', 'молчит': ' СТОЙ ',
      'не начал': ' ПУСТО', 'нет файла': ' НЕТ  ', 'связь не настроена': ' ???  '
    }[с.состояние] || '      ';
    console.log(метка + ' ' + с.кто);
    console.log('        ' + с.слова);
    if (с.что) console.log('        задача: ' + с.что.slice(0, 70));
  }
  console.log('');
  console.log(однойСтрокой(итог));
  if (итог.молчат) {
    console.log('Отличить «встал» от «ждёт долгую команду» по файлам нельзя — посмотрите сами,');
    console.log('прежде чем перезапускать: прерванного исполнителя молча не перезапускаем.');
  }
}

/* Запуск из командной строки. Когда файл просто подключают как модуль,
   ничего не печатается и не пишется. */
if (require.main === module) {
  напечатать(собрать(process.argv[2], true));
}

module.exports = {
  собрать: собрать,
  однойСтрокой: однойСтрокой,
  напечатать: напечатать,
  ПОРОГ_ПО_УМОЛЧАНИЮ: ПОРОГ_ПО_УМОЛЧАНИЮ
};
