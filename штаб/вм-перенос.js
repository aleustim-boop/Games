#!/usr/bin/env node
// Перенос папки данных на ВМ владельца через хаб.
// Режет файлы на куски base64, дописывает их на ВМ скриптами через штаб/вм.js,
// на последнем куске собирает файл обратно (base64 -d) и убирает временный .b64.
// В конце сверяет sha256 каждого файла: локально (node crypto) и на ВМ (sha256sum).
// Ключей и адресов (хаба, ВМ) сама не знает и не печатает — это дело штаб/вм.js.

const fs = require('fs');
const os = require('os');
const path = require('path');
const crypto = require('crypto');
const { execFileSync } = require('child_process');

const ВМ_JS = path.join(__dirname, 'вм.js');
const ВРЕМЕННАЯ_ПАПКА = fs.mkdtempSync(path.join(os.tmpdir(), 'вм-перенос-'));

let счётчикШагов = 0;

// ——— помощники для POSIX-путей и shell-кавычек (цель — линукс-ВМ, dash) ———

function posixJoin(...части) {
  return части.filter(Boolean).join('/').replace(/\/{2,}/g, '/');
}

function posixDirname(путь) {
  const срез = путь.lastIndexOf('/');
  return срез <= 0 ? '/' : путь.slice(0, срез);
}

/** Кавычки для POSIX sh: одинарные, с безопасным экранированием одинарной кавычки внутри. */
function shQuote(текст) {
  return "'" + String(текст).replace(/'/g, "'\\''") + "'";
}

function нормПуть(путь) {
  if (путь.length > 1 && путь.endsWith('/')) return путь.slice(0, -1);
  return путь;
}

// ——— сбор файлов ———

/** Рекурсивно собирает все файлы папки, отдаёт относительные пути со слэшем "/". */
function собратьФайлы(папка, базовая = папка) {
  const результат = [];
  for (const запись of fs.readdirSync(папка, { withFileTypes: true })) {
    const полный = path.join(папка, запись.name);
    if (запись.isDirectory()) {
      результат.push(...собратьФайлы(полный, базовая));
    } else if (запись.isFile()) {
      результат.push(path.relative(базовая, полный).split(path.sep).join('/'));
    }
  }
  return результат.sort();
}

function разбить(текст, размер) {
  const куски = [];
  for (let i = 0; i < текст.length; i += размер) куски.push(текст.slice(i, i + размер));
  if (куски.length === 0) куски.push(''); // пустой файл — один пустой кусок
  return куски;
}

// ——— устройство ———

function разобратьСписокУстройств(текст) {
  const строки = [];
  for (const линия of текст.split(/\r?\n/)) {
    const м = линия.match(/^-\s*id=(\S+)\s*\|\s*имя=(.*?)\s*\|\s*ОС=(.*?)\s*\|\s*онлайн=(.*)$/);
    if (м) строки.push({ id: м[1], имя: м[2], ос: м[3], онлайн: м[4] });
  }
  return строки;
}

function получитьУстройство() {
  const переопределение = process.env.ВМ_ПЕРЕНОС_УСТРОЙСТВО;
  if (переопределение) return переопределение;
  const вывод = execFileSync(process.execPath, [ВМ_JS, 'устройства'], {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'inherit'],
  });
  const список = разобратьСписокУстройств(вывод);
  if (список.length === 0) {
    console.error('Хаб не отдал ни одной машины — переносить некуда.');
    process.exit(1);
  }
  const онлайн = список.filter((з) => /да|true|online/i.test(з.онлайн));
  const кандидаты = онлайн.length ? онлайн : список;
  if (кандидаты.length > 1) {
    console.error('Машин несколько (' + кандидаты.length + '), программа рассчитана на одну. Укажите явно через переменную ВМ_ПЕРЕНОС_УСТРОЙСТВО=<id>.');
    process.exit(1);
  }
  return кандидаты[0].id;
}

// ——— запуск шага на ВМ через штаб/вм.js ———

/** Пишет скрипт во временный файл, зовёт "штаб/вм.js выполнить", разбирает код возврата. */
function выполнитьНаВМ(id, текстСкрипта, подпись, { строго = true } = {}) {
  счётчикШагов += 1;
  const файлСкрипта = path.join(ВРЕМЕННАЯ_ПАПКА, 'шаг-' + счётчикШагов + '.sh');
  fs.writeFileSync(файлСкрипта, текстСкрипта, 'utf8');
  let вывод;
  try {
    вывод = execFileSync(process.execPath, [ВМ_JS, 'выполнить', id, файлСкрипта, 'bash'], {
      encoding: 'utf8',
      maxBuffer: 20 * 1024 * 1024,
      stdio: ['ignore', 'pipe', 'inherit'],
    });
  } catch (ошибка) {
    console.error('Запуск на ВМ упал (' + (подпись || 'шаг ' + счётчикШагов) + '): ' + ошибка.message);
    process.exit(1);
  }
  const совпадение = вывод.match(/код возврата:\s*(-?\d+)/);
  const код = совпадение ? совпадение[1] : undefined;
  if (код !== '0') {
    const сообщение = 'Шаг на ВМ вернул код ' + (код === undefined ? '(не найден)' : код) + (подпись ? ' — ' + подпись : '');
    if (строго) {
      console.error(сообщение);
      console.error(вывод.slice(0, 4000));
      process.exit(1);
    } else {
      console.error('Замечание: ' + сообщение);
    }
  }
  return вывод;
}

// ——— перенос одного файла ———

function перенестиФайл(id, локальныйПуть, вмПуть, размерКуска, индекс, всего) {
  const данные = fs.readFileSync(локальныйПуть);
  const base64 = данные.toString('base64');
  const куски = разбить(base64, размерКуска);
  const вмB64 = вмПуть + '.b64';
  console.log('[' + индекс + '/' + всего + '] ' + вмПуть + ' — ' + данные.length + ' байт, кусков: ' + куски.length);
  for (let i = 0; i < куски.length; i++) {
    const строки = [];
    if (i === 0) {
      строки.push('mkdir -p ' + shQuote(posixDirname(вмB64)));
      строки.push('rm -f ' + shQuote(вмB64)); // на случай обрывка от прошлой попытки
    }
    строки.push('printf \'%s\' ' + shQuote(куски[i]) + ' >> ' + shQuote(вмB64));
    if (i === куски.length - 1) {
      строки.push('base64 -d ' + shQuote(вмB64) + ' > ' + shQuote(вмПуть));
      строки.push('rm -f ' + shQuote(вмB64));
    }
    выполнитьНаВМ(id, строки.join('\n') + '\n', 'кусок ' + (i + 1) + '/' + куски.length + ' файла ' + вмПуть);
  }
}

// ——— сверка sha256 ———

function сверитьSha256(id, локальнаяПапка, путьКуда, файлы) {
  const локальные = файлы.map((отн) => {
    const данные = fs.readFileSync(path.join(локальнаяПапка, ...отн.split('/')));
    return {
      файл: отн,
      размер: данные.length,
      sha256: crypto.createHash('sha256').update(данные).digest('hex'),
    };
  });

  const строкиСкрипта = ['cd ' + shQuote(путьКуда) + ' || { echo ПАПКА_НЕ_НАЙДЕНА; exit 1; }'];
  for (const з of локальные) строкиСкрипта.push('sha256sum -- ' + shQuote(з.файл));
  const вывод = выполнитьНаВМ(id, строкиСкрипта.join('\n') + '\n', 'сверка sha256', { строго: false });

  const блок = вывод.match(/=== вывод ===\n([\s\S]*?)\n=== /);
  const текстВывода = блок ? блок[1] : вывод;
  const хэшиНаВМ = new Map();
  for (const линия of текстВывода.split(/\r?\n/)) {
    const м = линия.match(/^([0-9a-fA-F]{64})\s+\*?(.+)$/);
    if (м) хэшиНаВМ.set(м[2], м[1].toLowerCase());
  }

  return локальные.map((з) => {
    const наВМ = хэшиНаВМ.get(з.файл);
    return { файл: з.файл, размер: з.размер, совпало: !!наВМ && наВМ === з.sha256 };
  });
}

function напечататьТаблицу(строки) {
  console.log('\nфайл — размер (байт) — sha256');
  for (const с of строки) {
    console.log(с.файл + ' — ' + с.размер + ' — ' + (с.совпало ? 'совпало' : 'НЕ совпало'));
  }
}

// ——— командная строка ———

function помощь() {
  console.log([
    'Перенос папки данных на ВМ владельца через хаб (штаб/вм.js).',
    '',
    '  node штаб/вм-перенос.js <папка-откуда> <путь-куда-на-ВМ> [--проба] [--кусок=N]',
    '',
    '  --проба      пометить перенос как пробный (в шапке вывода), поведение не меняет',
    '  --кусок=N    размер куска base64-текста на один запуск ВМ, байт (по умолчанию 60000)',
    '',
    'Переменные окружения:',
    '  ВМ_ПЕРЕНОС_УСТРОЙСТВО   id устройства на хабе — если машин несколько, задать явно',
    '  ВМ_ПЕРЕНОС_КУСОК        то же, что --кусок',
    '',
    'Ничего, кроме указанной папки на ВМ, не трогает: служб, портов, systemctl не касается.',
    'Несовпадение sha256 хотя бы одного файла — выход с кодом 1.',
  ].join('\n'));
}

async function главная() {
  const доводы = process.argv.slice(2);
  if (доводы.length === 0 || доводы[0] === '--help' || доводы[0] === '-h' || доводы[0] === 'помощь') {
    помощь();
    return;
  }
  const позиционные = доводы.filter((д) => !д.startsWith('--'));
  const проба = доводы.includes('--проба');
  let размерКуска = Number(process.env.ВМ_ПЕРЕНОС_КУСОК) || 60000;
  for (const д of доводы) {
    const м = д.match(/^--кусок=(\d+)$/);
    if (м) размерКуска = Number(м[1]);
  }

  const [папкаДоводОткуда, путьКудаДовод] = позиционные;
  if (!папкаДоводОткуда || !путьКудаДовод) {
    помощь();
    process.exit(1);
  }
  const папкаОткуда = path.resolve(папкаДоводОткуда);
  const путьКуда = нормПуть(путьКудаДовод);

  if (!путьКуда.startsWith('/') || /^\/[A-Za-z]:/.test(путьКуда)) {
    console.error('Путь на ВМ должен начинаться с "/" и не быть похож на "C:/...": получено "' + путьКуда + '".');
    console.error('Похоже на след MSYS-конвертации пути (Git Bash переписывает "/tmp/..." в "C:/Users/..."). Зовите через PowerShell или ставьте MSYS_NO_PATHCONV=1.');
    process.exit(1);
  }

  if (!fs.existsSync(папкаОткуда) || !fs.statSync(папкаОткуда).isDirectory()) {
    console.error('Нет такой папки: ' + папкаОткуда);
    process.exit(1);
  }

  const файлы = собратьФайлы(папкаОткуда);
  if (файлы.length === 0) {
    console.error('В папке нет файлов: ' + папкаОткуда);
    process.exit(1);
  }

  console.log((проба ? 'ПРОБНЫЙ перенос' : 'Перенос') + ': файлов ' + файлы.length + ', размер куска ' + размерКуска + ' байт.');

  const id = получитьУстройство();

  let индекс = 0;
  for (const отн of файлы) {
    индекс += 1;
    const локальныйПуть = path.join(папкаОткуда, ...отн.split('/'));
    const вмПуть = posixJoin(путьКуда, отн);
    перенестиФайл(id, локальныйПуть, вмПуть, размерКуска, индекс, файлы.length);
  }

  const таблица = сверитьSha256(id, папкаОткуда, путьКуда, файлы);
  напечататьТаблицу(таблица);

  const естьРасхождения = таблица.some((с) => !с.совпало);
  if (естьРасхождения) {
    console.error('\nЕсть расхождения sha256 — перенос НЕ подтверждён.');
    process.exit(1);
  }
  console.log('\nВсе файлы совпали по sha256.');
}

главная().catch((ошибка) => {
  console.error('Сбой: ' + ошибка.message);
  process.exit(1);
});
