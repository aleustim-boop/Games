/*
  Сторож дашборда штаба: держит отдельный долгоживущий процесс, который
  раз в несколько минут спрашивает у дашборда «ты жив?» (GET /жив) и,
  если тот молчит, поднимает его заново через штаб/перезапуск-дашборда.js.

  Зачем отдельная программа — 11 сентября дашборд упал молча: процесс исчез,
  а в журнале не осталось ни строки о причине (совпало с перегрузкой машины
  параллельными браузерными прогонами). Штаб заметил и перезапустил руками,
  но владелец в это время видел бы неотвечающую страницу. Сторож закрывает
  именно этот пробел: замечает падение сам и оставляет след в журнале —
  без следа в журнале сама эта поломка не отличима от «просто работает».

  Запуск:
      node штаб/сторож-дашборда.js                      (порт 8791, каждые 3 минуты, уходит в фон)
      node штаб/сторож-дашборда.js 8799 3000             (свой порт и интервал в мс)
      node штаб/сторож-дашборда.js 8791 180000 --передний-план   (не уходить в фон — видно в консоли)

  Без «--передний-план» программа сама поднимает detached-копию себя же с этим
  флагом и сразу завершается — тем же паттерном, что штаб/перезапуск-дашборда.js
  поднимает новый дашборд: spawn + unref, вывод в тот же журнал.

  Кто сторожит сторожа — вне этой задачи, сознательно не решаем.
*/

'use strict';

const { spawn } = require('child_process');
const fs = require('fs');
const http = require('http');
const path = require('path');

const { перезапустить, строкаЗапуска } = require('./перезапуск-дашборда.js');

const корень = path.join(__dirname, '..');
const журнал = path.join(__dirname, 'дашборд.log');
const файлPid = path.join(__dirname, 'сторож-дашборда.pid');

const ПОРТ_ПО_УМОЛЧАНИЮ = 8791;
const ИНТЕРВАЛ_ПО_УМОЛЧАНИЮ_МС = 180000; // 3 минуты
const СРОК_ОТВЕТА_МС = 5000;

/* Разбор аргументов командной строки: порт, интервал_мс, --передний-план — в любом порядке.
   Мусор в аргументах (порт вне 1..65535, интервал <= 0) молча откатывается
   на значения по умолчанию — опечатка в запуске не должна класть сторож
   в бессмысленное состояние (например, setInterval с отрицательным числом). */
function разобратьАргументы(аргументы) {
  const передПлан = аргументы.includes('--передний-план');
  const числа = аргументы.filter(function (а) { return /^\d+$/.test(а); });

  let порт = числа.length > 0 ? Number(числа[0]) : ПОРТ_ПО_УМОЛЧАНИЮ;
  if (!Number.isInteger(порт) || порт < 1 || порт > 65535) порт = ПОРТ_ПО_УМОЛЧАНИЮ;

  let интервал = числа.length > 1 ? Number(числа[1]) : ИНТЕРВАЛ_ПО_УМОЛЧАНИЮ_МС;
  if (!Number.isInteger(интервал) || интервал <= 0) интервал = ИНТЕРВАЛ_ПО_УМОЛЧАНИЮ_МС;

  return { порт: порт, интервал: интервал, передПлан: передПлан };
}

/* Время строкой для журнала — местное, секунды важны (падение — дело нескольких минут). */
function штампВремени() {
  return new Date().toLocaleString('ru-RU');
}

/* Последняя линия обороны: если даже запись в журнал не удалась (диск полон,
   файл занят, нет прав) — сторожу больше некуда сообщить об этом. Молча
   продолжаем жить, а не роняем необработанным исключением процесс, единственная
   задача которого — не падать молча (иначе один сбой записи валит весь сторож). */
function дописатьВЖурнал(строка) {
  try {
    fs.appendFileSync(журнал, '[' + штампВремени() + '] ' + строка + '\n');
  } catch (ошибка) {
    // некуда написать про эту ошибку — умышленно проглатываем
  }
}

/* Интервал по-человечески: минуты, если делится ровно, иначе секунды. */
function по_человечески_интервал(мс) {
  if (мс % 60000 === 0) {
    const минут = мс / 60000;
    return минут + ' мин';
  }
  return Math.round(мс / 1000) + ' с';
}

/* Жив ли процесс с таким PID — Windows: process.kill(pid, 0) кидает исключение, если нет. */
function процессЖив(pid) {
  try {
    process.kill(pid, 0);
    return true;
  } catch (ошибка) {
    return false;
  }
}

/**
 * Это именно наш сторож, а не случайно переиспользованный Windows'ом
 * тот же номер PID под другую программу? Переиспользуем строкаЗапуска()
 * из штаб/перезапуск-дашборда.js — та же PowerShell-проверка командной
 * строки, что уже отличает дашборд от чужого процесса на его порту.
 * Проверка не удалась (PowerShell недоступен и т.п.) — считаем, что это
 * НЕ сторож: безопаснее перезапуститься лишний раз, чем упустить присмотр
 * за дашбордом насовсем из-за одного старого PID-файла.
 */
function этоСторож(pid) {
  return new Promise(function (готово) {
    try {
      const строка = строкаЗапуска(pid);
      готово(typeof строка === 'string' && /(^|[\s"'\\/])сторож-дашборда\.js(?=["'\s]|$)/i.test(строка));
    } catch (ошибка) {
      готово(false);
    }
  });
}

/* Один запрос «ты жив?» — вернёт { ок, причина }. ок:true только на 200 и теле «жив». */
function спроситьЖив(порт) {
  return new Promise(function (готово) {
    const запрос = http.get('http://127.0.0.1:' + порт + '/жив', { timeout: СРОК_ОТВЕТА_МС }, function (ответ) {
      let тело = '';
      ответ.on('data', function (кусок) { тело += кусок; });
      ответ.on('end', function () {
        if (ответ.statusCode !== 200) {
          готово({ ок: false, причина: 'дашборд ответил кодом ' + ответ.statusCode });
          return;
        }
        if (тело.trim() !== 'жив') {
          готово({ ок: false, причина: 'дашборд ответил 200, но не тем телом: «' + тело.trim().slice(0, 80) + '»' });
          return;
        }
        готово({ ок: true, причина: '' });
      });
    });
    запрос.on('timeout', function () {
      запрос.destroy();
      готово({ ок: false, причина: 'дашборд не ответил за ' + Math.round(СРОК_ОТВЕТА_МС / 1000) + 'с — таймаут' });
    });
    запрос.on('error', function (ошибка) {
      готово({ ок: false, причина: 'соединение с дашбордом не удалось (' + ошибка.code + ')' });
    });
  });
}

/* Один тик проверки: молчим на успехе, пишем в журнал и чиним при неудаче.
   Тело завёрнуто в try/catch — необработанная ошибка внутри (например,
   перезапустить() или сама запись в журнал) не должна ронять весь процесс
   сторожа: без этого один случайный сбой лишает дашборд присмотра насовсем. */
async function проверитьИПочинить(порт) {
  try {
    const итогПроверки = await спроситьЖив(порт);
    if (итогПроверки.ок) return; // всё в порядке — журнал не пачкаем

    дописатьВЖурнал('сторож: ' + итогПроверки.причина);

    const итогПерезапуска = await перезапустить(порт);
    const сутьСлов = итогПерезапуска.слова.join('; ');
    дописатьВЖурнал('сторож: перезапуск — ' + сутьСлов + ' — итог: ' + (итогПерезапуска.ок ? 'ок' : 'НЕ удалось'));
  } catch (ошибка) {
    дописатьВЖурнал('сторож: неожиданная ошибка в тике проверки — ' + (ошибка && ошибка.message ? ошибка.message : String(ошибка)));
  }
}

/* Поднять detached-копию себя же с флагом --передний-план и завершиться. */
function уйтиВФон(порт, интервал) {
  const поток = fs.openSync(журнал, 'a');
  const дитя = spawn(process.execPath,
    [__filename, String(порт), String(интервал), '--передний-план'],
    { cwd: корень, detached: true, windowsHide: true, stdio: ['ignore', поток, поток] });
  дитя.unref();
  console.log('сторож дашборда поднят в фоне, номер процесса ' + дитя.pid + ', журнал: штаб/дашборд.log');
}

/* Работа в переднем плане: проверка живого дубликата, PID-файл, сам интервал. */
async function запуститьВПереднемПлане(порт, интервал) {
  if (fs.existsSync(файлPid)) {
    const старыйPid = Number(fs.readFileSync(файлPid, 'utf8').trim());
    if (Number.isInteger(старыйPid) && старыйPid > 0 && процессЖив(старыйPid) && await этоСторож(старыйPid)) {
      дописатьВЖурнал('сторож: уже запущен другой сторож (номер процесса ' + старыйPid + ') — этот экземпляр завершается, чтобы не плодить дублей');
      return;
    }
  }
  fs.writeFileSync(файлPid, String(process.pid));

  /* Стереть свой PID-файл при штатном завершении — иначе после аварийной
     остановки (или обычного закрытия) в файле надолго остаётся номер,
     который Windows рано или поздно отдаст совсем другой программе, и
     следующий запуск сторожа примет её за уже работающего себя и молча
     выйдет, оставив дашборд без присмотра. Сверяем PID перед удалением —
     файл мог быть уже переписан более новым запуском сторожа. */
  function убратьPidФайл() {
    try {
      if (fs.existsSync(файлPid) && Number(fs.readFileSync(файлPid, 'utf8').trim()) === process.pid) {
        fs.unlinkSync(файлPid);
      }
    } catch (ошибка) {
      // не удалось стереть — переживём при следующем запуске через сверку живости и этоСторож()
    }
  }
  process.on('exit', убратьPidФайл);
  process.on('SIGINT', function () { process.exit(0); });
  process.on('SIGTERM', function () { process.exit(0); });

  дописатьВЖурнал('сторож дашборда запущен, порт ' + порт + ', проверяю каждые ' + по_человечески_интервал(интервал));

  /* Флаг занятости — защита от наложения тиков: если проверитьИПочинить
     (внутри которой перезапустить() может ждать до ~30с) не успела закончиться
     к следующему setInterval, новый тик молча пропускается, а не стартует
     параллельно поверх ещё не завершённого — иначе получим два одновременных
     перезапустить() на один и тот же порт. */
  let тикИдёт = false;
  setInterval(function () {
    if (тикИдёт) return; // предыдущий тик ещё не закончился — пропускаем молча
    тикИдёт = true;
    проверитьИПочинить(порт).finally(function () { тикИдёт = false; });
  }, интервал);
}

if (require.main === module) {
  const настройки = разобратьАргументы(process.argv.slice(2));
  if (настройки.передПлан) {
    запуститьВПереднемПлане(настройки.порт, настройки.интервал).catch(function (ошибка) {
      дописатьВЖурнал('сторож: неожиданная ошибка при запуске — ' + (ошибка && ошибка.message ? ошибка.message : String(ошибка)));
    });
  } else {
    уйтиВФон(настройки.порт, настройки.интервал);
  }
}
