/*
  Перезапуск сервера комнат одной командой.

  Зачем отдельная программа. Раньше штаб делал это в три приёма: найти, кто
  занял порт, снять его через PowerShell, поднять заново. Каждый приём — своё
  окно «разрешить?» у владельца, а он сидит перед экраном и не может следить
  за нами постоянно. Теперь это одна короткая команда:

      node штаб/перезапуск-сервера.js

  Порт по умолчанию 8790 — не 8765: тот на этой машине занят чужой программой,
  и сервер там молча недостижим. Другой порт можно передать доводом.
*/

const { execFileSync, spawn } = require('child_process');
const fs = require('fs');
const path = require('path');

const порт = process.argv[2] || '8790';
const корень = path.join(__dirname, '..');
const журнал = path.join(корень, 'штаб', 'сервер.log');

/* Кто сейчас слушает порт. Пусто — значит никто, и это не беда. */
function ктоНаПорту(порт) {
  try {
    const вывод = execFileSync('netstat', ['-ano', '-p', 'TCP'], { encoding: 'utf8' });
    const номера = new Set();
    for (const строка of вывод.split('\n')) {
      /* Ищем именно слушающий сокет: строки с чужими подключениями к нам
         содержат тот же порт, но снимать по ним нельзя — это не наш сервер. */
      if (!/LISTENING/i.test(строка)) continue;
      const части = строка.trim().split(/\s+/);
      const адрес = части[1] || '';
      if (!адрес.endsWith(':' + порт)) continue;
      const номер = части[части.length - 1];
      if (/^\d+$/.test(номер) && номер !== '0') номера.add(номер);
    }
    return [...номера];
  } catch (е) {
    return [];
  }
}

const занявшие = ктоНаПорту(порт);
for (const номер of занявшие) {
  try {
    execFileSync('taskkill', ['/PID', номер, '/F'], { stdio: 'ignore' });
    console.log('снял старый сервер, номер процесса ' + номер);
  } catch (е) {
    console.log('не смог снять процесс ' + номер + ' — возможно, он уже закрылся');
  }
}
if (занявшие.length === 0) console.log('порт ' + порт + ' был свободен');

/* Поднимаем заново. Отвязываем от этой программы, чтобы сервер пережил её. */
const поток = fs.openSync(журнал, 'a');
const дитя = spawn(process.execPath, [path.join(корень, 'server', 'сервер.js'), порт], {
  cwd: корень,
  detached: true,
  stdio: ['ignore', поток, поток],
});
дитя.unref();

/* Ждём чуть-чуть и проверяем, что он правда отвечает: «запустил» без проверки
   — это обещание, а не факт, а обещаний в отчётах штаба быть не должно. */
setTimeout(() => {
  const запрос = require('http').get('http://127.0.0.1:' + порт + '/', (ответ) => {
    let тело = '';
    ответ.on('data', (к) => (тело += к));
    ответ.on('end', () => console.log('сервер отвечает: ' + тело.slice(0, 80)));
  });
  запрос.on('error', () => {
    console.log('сервер НЕ отвечает — смотрите ' + журнал);
    process.exitCode = 1;
  });
}, 2500);
