/* Куда ведёт кнопка «Задания для ChatGPT» при 0, 1 и 2 открытых — на подставных записях.

       node штаб/проверки/проверка-кнопки.js
*/
'use strict';
const path = require('path');
const важное = require(path.join(__dirname, '..', 'важное-страница.js'));

const открытое = function (ключ) { return { ключ: ключ, вид: 'нужен ответ', заданиеЧатгпт: true }; };
const решённое = function (ключ) { return { ключ: ключ, вид: 'решено', заданиеЧатгпт: true }; };
const чужое = { ключ: 'не-задание', вид: 'нужен ответ', заданиеЧатгпт: false };

const случаи = [
  { имя: 'ни одного задания', записи: [чужое], ждём: null },
  { имя: 'только решённые', записи: [решённое('р1'), чужое], ждём: '/задания-чатгпт' },
  { имя: 'одно открытое', записи: [открытое('раз'), решённое('р1'), чужое], ждём: '/важное/' + encodeURIComponent('раз') },
  { имя: 'два открытых', записи: [открытое('раз'), открытое('два'), решённое('р1')], ждём: '/задания-чатгпт' }
];

let провалов = 0;
for (const с of случаи) {
  const кнопка = важное.кнопкаЗаданий(с.записи);
  const найдено = /href="([^"]*)"/.exec(кнопка);
  const куда = найдено ? найдено[1] : null;
  const число = /кнопка-заданий__число">(\d+)</.exec(кнопка);
  const ок = куда === с.ждём;
  if (!ок) провалов += 1;
  console.log((ок ? '  ок   ' : '  ПРОВАЛ ') + с.имя + ': ведёт ' + (куда || 'кнопки нет') + (число ? ', на кнопке ' + число[1] : ''));
}
console.log('провалов: ' + провалов);
process.exitCode = провалов ? 1 : 0;
