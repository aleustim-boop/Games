/* Главная «Важного»: что остаётся за сутки и что уходит за «Показать всё».

       node штаб/проверки/проверка-суток.js

   Подставные записи, свои «сейчас», версия суточной давности и время правки.
   Потом то же на копии кода, где мерка суток сломана нарочно, — проверка
   обязана покраснеть. */
'use strict';

const fs = require('fs');
const path = require('path');
const Module = require('module');

const ПУТЬ = path.join(__dirname, '..', 'важное-страница.js');
const МЕСЯЦЫ = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];
const ЧАС = 3600 * 1000;
const сейчас = new Date(2026, 8, 10, 20, 0).getTime();
const дв = function (ч) { return String(ч).padStart(2, '0'); };

function появилосьЗа(часов) {
  const д = new Date(сейчас - часов * ЧАС);
  return д.getDate() + ' ' + МЕСЯЦЫ[д.getMonth()] + ', ' + дв(д.getHours()) + ':' + дв(д.getMinutes());
}
function открытоЗа(часов) {
  const д = new Date(сейчас - часов * ЧАС);
  return дв(д.getDate()) + '.' + дв(д.getMonth() + 1) + ', ' + дв(д.getHours()) + ':' + дв(д.getMinutes());
}
function запись(ключ, вид, свойства) {
  return Object.assign({
    ключ: ключ, заголовок: 'Заголовок ' + ключ, суть: 'суть ' + ключ, вид: вид,
    порядок: { 'нужен ответ': 0, 'к сведению': 1, 'решено': 2 }[вид],
    появилось: null, открытоКогда: null, новое: true, ответ: null, чемКончилось: ''
  }, свойства);
}

const записи = [
  запись('старый-вопрос', 'нужен ответ', { появилось: появилосьЗа(120) }),
  запись('свежая-сведения', 'к сведению', { появилось: появилосьЗа(2) }),
  запись('старая-сведения', 'к сведению', { появилось: появилосьЗа(72) }),
  запись('старая-открытая', 'к сведению', { появилось: появилосьЗа(72), открытоКогда: открытоЗа(1), новое: false }),
  запись('открыта-давно', 'к сведению', { появилось: появилосьЗа(72), открытоКогда: открытоЗа(30), новое: false }),
  запись('решена-с-ответом', 'решено', { появилось: появилосьЗа(30), чемКончилось: 'Владелец выбрал ноль, и шкала теперь такая',
    ответ: { имя: 'Ноль', кнопка: 'ноль', 'когда точно': new Date(сейчас - 2 * ЧАС).toISOString() } }),
  запись('старая-решённая', 'решено', { появилось: появилосьЗа(72), чемКончилось: 'решили давно' }),
  запись('решена-сегодня-без-ответа', 'решено', { появилось: появилосьЗа(72), чемКончилось: 'решили сегодня словами' }),
  запись('свежая-решённая', 'решено', { появилось: появилосьЗа(2), чемКончилось: 'рисовать не пришлось' })
];
const решеноСуткиНазад = new Set(['старая-решённая']);
const правка = new Date(сейчас - 10 * 60 * 1000);   // файл правили 10 минут назад: 19:50

/** Загрузить модуль — настоящий или копию с подменённым кодом. */
function загрузить(замена) {
  let исходник = fs.readFileSync(ПУТЬ, 'utf8');
  if (замена) {
    const было = исходник;
    исходник = исходник.replace(/function свежееСуток\(дата, сейчас\) \{[\s\S]*?\n\}/, замена);
    if (исходник === было) throw new Error('поломка не встала: функция «свежееСуток» не найдена — проверка слепа');
  }
  const м = new Module(ПУТЬ, null);
  м.filename = ПУТЬ;
  м.paths = Module._nodeModulePaths(path.dirname(ПУТЬ));
  м._compile(исходник, ПУТЬ);
  return м.exports;
}

function показано(html) {
  const ключи = [];
  const образец = /href="\/важное\/([^"]+)"/g;
  let н;
  while ((н = образец.exec(html))) ключи.push(decodeURIComponent(н[1]));
  return ключи;
}

function прогон(модуль, заголовок, условия) {
  let провалов = 0;
  const проверить = function (да, что) { if (!да) провалов += 1; console.log((да ? '  ок   ' : '  ПРОВАЛ ') + что); };
  console.log(заголовок);
  const у = Object.assign({ записи: записи, сейчас: сейчас, решеноСуткиНазад: решеноСуткиНазад, правка: правка }, условия || {});
  const html = модуль.блокДляГлавной(у);
  const ключи = показано(html);
  const граница = html.indexOf('Решено за сутки');
  const вРешённых = function (к) { const где = html.indexOf('/важное/' + encodeURIComponent(к)); return граница >= 0 && где > граница; };
  const вКарточках = function (к) { const где = html.indexOf('/важное/' + encodeURIComponent(к)); return где >= 0 && (граница < 0 || где < граница); };
  return { html: html, ключи: ключи, проверить: проверить, вРешённых: вРешённых, вКарточках: вКарточках, провалов: function () { return провалов; } };
}

function основныеПроверки(р) {
  const есть = function (к) { return р.ключи.indexOf(к) !== -1; };
  р.проверить(есть('старый-вопрос') && р.вКарточках('старый-вопрос'), 'вопрос без ответа на главной, хоть ему пять дней');
  р.проверить(есть('свежая-сведения') && р.вКарточках('свежая-сведения'), 'свежая «к сведению» — карточкой');
  р.проверить(!есть('старая-сведения'), 'старая «к сведению», не открытая, — за «Показать всё»');
  р.проверить(есть('старая-открытая') && р.вКарточках('старая-открытая'), 'старую, но открытую час назад, не прячем');
  р.проверить(!есть('открыта-давно'), 'открытую 30 часов назад — прячем');
  р.проверить(есть('решена-с-ответом') && р.вРешённых('решена-с-ответом'), 'решённая с ответом 2 часа назад — внизу, строкой');
  р.проверить(!есть('старая-решённая'), 'решённую ещё сутки назад — прячем');
  р.проверить(есть('решена-сегодня-без-ответа') && р.вРешённых('решена-сегодня-без-ответа'), 'сутки назад не решена, теперь решена — внизу');
  р.проверить(есть('свежая-решённая') && р.вРешённых('свежая-решённая'), 'свежая решённая — внизу, строкой');
}

let всегоПровалов = 0;

// 1. Честный прогон
{
  const модуль = загрузить(null);
  const р = прогон(модуль, '1. Настоящий код');
  основныеПроверки(р);
  р.проверить(/ваш ответ в 18:00/.test(р.html), 'у отвеченной подпись «ваш ответ в 18:00» — время из ответа');
  р.проверить((р.html.match(/решено не позже 19:50/g) || []).length === 2, 'у решённых без ответа «решено не позже 19:50» — время правки файла');
  р.проверить(/Владелец выбрал ноль/.test(р.html), 'в строке решённого — начало «чем кончилось»');
  р.проверить((р.html.match(/важное--строкой/g) || []).length === 3, 'решённых строк ровно три');
  р.проверить(/Показать всё: ещё 3 старше суток \(из них решённых: 1\)/.test(р.html), 'за «Показать всё» ровно три, из них одна решённая');
  const карточкаСвежей = р.html.slice(р.html.indexOf('/важное/' + encodeURIComponent('свежая-сведения')), р.html.indexOf('/важное/' + encodeURIComponent('свежая-сведения')) + 400);
  const карточкаОткрытой = р.html.slice(р.html.indexOf('/важное/' + encodeURIComponent('старая-открытая')), р.html.indexOf('/важное/' + encodeURIComponent('старая-открытая')) + 400);
  р.проверить(/важное-новое/.test(карточкаСвежей) && !/важное-новое/.test(карточкаОткрытой), 'метка «новое» только у неоткрытой');
  всегоПровалов += р.провалов();

  const безGit = прогон(модуль, '1б. Git молчит — о свежести решения не знаем', { решеноСуткиНазад: null });
  безGit.проверить(безGit.ключи.indexOf('решена-сегодня-без-ответа') === -1, 'без git не выдумываем: решённая без ответа и старая — за «Показать всё»');
  безGit.проверить(безGit.ключи.indexOf('свежая-решённая') !== -1, 'свежая по «появилось» остаётся и без git');
  всегоПровалов += безGit.провалов();

  const давноПравили = прогон(модуль, '1в. Файл не правили двое суток', { правка: new Date(сейчас - 48 * ЧАС) });
  давноПравили.проверить(давноПравили.ключи.indexOf('решена-сегодня-без-ответа') === -1, 'файл не правили сутки — ничего в нём за сутки не решали');
  давноПравили.проверить(/решено не позже 8 сентября, 20:00/.test(давноПравили.html), 'подпись старой правки — с датой: «не позже 8 сентября, 20:00»');
  всегоПровалов += давноПравили.провалов();
}
console.log('   провалов в честном прогоне: ' + всегоПровалов);

// 2. Поломки мерки суток — обязаны покраснеть
const провалыПоломок = [];
for (const [имя, замена] of [
  ['всё свежее', 'function свежееСуток() { return true; }'],
  ['ничего не свежее', 'function свежееСуток() { return false; }']
]) {
  const р = прогон(загрузить(замена), '2. Поломка «' + имя + '»');
  основныеПроверки(р);
  провалыПоломок.push(р.провалов());
  console.log('   провалов: ' + р.провалов() + (р.провалов() > 0 ? ' — проверка это видит' : ' — ПРОВЕРКА СЛЕПА'));
}

const итог = всегоПровалов === 0 && провалыПоломок.every(function (п) { return п > 0; });
console.log(итог ? 'ИТОГ: всё верно, и проверка умеет краснеть' : 'ИТОГ: НЕ СХОДИТСЯ');
process.exitCode = итог ? 0 : 1;
