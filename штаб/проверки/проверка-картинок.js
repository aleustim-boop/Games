/* Картинки в записях дашборда: сервер отдаёт только снимки/ и эталон/, png и jpg.

       node штаб/проверки/проверка-картинок.js            — настоящая защита: злые запросы получают отказ
       node штаб/проверки/проверка-картинок.js поломка    — защита заменена наивной склейкой пути:
                                                           проверка обязана покраснеть

   Поднимает копию штаб/дашборд.js на своём порту (8811, в «поломке» 8812);
   пересборка списков в копии выключена — ЗАДАЧИ.md не трогаем.

   Секрет не читается ни в каком режиме: даже в «поломке» проверка расширения
   остаётся, и .env не отдаётся — поломку ловит настоящий jpg ВНЕ разрешённых папок.
   Тела ответов на злые запросы не печатаются. */
'use strict';

const fs = require('fs');
const path = require('path');
const http = require('http');
const Module = require('module');

const ПУТЬ = path.join(__dirname, '..', 'дашборд.js');
const поломка = process.argv[2] === 'поломка';
const ПОРТ = поломка ? 8812 : 8811;

let исходник = fs.readFileSync(ПУТЬ, 'utf8');
const безПересборки = исходник.replace('  пересобратьБезПадения();\n  setInterval(пересобратьБезПадения, ШАГ_ПЕРЕСБОРКИ_МС);', '');
if (безПересборки === исходник) throw new Error('не нашёл запуск пересборки — копию сервера поднимать нельзя');
исходник = безПересборки;
if (поломка) {
  const было = исходник;
  исходник = исходник.replace(/function файлКартинки\(адрес\) \{[\s\S]*?\n\}/,
    'function файлКартинки(адрес) {\n  const файл = path.join(КОРЕНЬ, адрес);\n  return ТИПЫ_КАРТИНОК[path.extname(файл).toLowerCase()] && fs.existsSync(файл) ? файл : null;\n}');
  if (исходник === было) throw new Error('поломка не встала: «файлКартинки» не найдена — проверка слепа');
}

process.argv[2] = String(ПОРТ);
const м = new Module(ПУТЬ, null);
м.filename = ПУТЬ;
м.paths = Module._nodeModulePaths(path.dirname(ПУТЬ));
м._compile(исходник, ПУТЬ);

const к = encodeURIComponent;
function спросить(адрес, метод) {
  return new Promise(function (готово) {
    const запрос = http.request({ host: '127.0.0.1', port: ПОРТ, path: адрес, method: метод || 'GET', timeout: 10000 }, function (ответ) {
      const куски = [];
      ответ.on('data', function (кусок) { куски.push(кусок); });
      ответ.on('end', function () { готово({ код: ответ.statusCode, тип: ответ.headers['content-type'] || '', тело: Buffer.concat(куски) }); });
    });
    запрос.on('timeout', function () { запрос.destroy(); });
    запрос.on('error', function (е) { готово({ код: 0, тип: '', тело: Buffer.from(String(е.message)) }); });
    запрос.end();
  });
}

const ЗЛЫЕ = [
  '/' + к('снимки') + '/../bot/.env',
  '/' + к('снимки') + '/..%2Fbot%2F.env',
  '/' + к('снимки') + '/%2e%2e%2fbot%2f.env',
  '/' + к('снимки') + '/..%5Cbot%5C.env',
  '/' + к('эталон') + '/../../../../Windows/win.ini',
  '/' + к('снимки') + '/.env',
  '/' + к('снимки') + '/../img/' + к('витрина') + '/durak.jpg',
  '/' + к('эталон') + '/..%2Fimg%2F' + к('витрина') + '%2Fdurak.jpg',
  '/' + к('снимки') + '/' + к('витрина-390.png') + '%00.txt',
  '/' + к('снимки') + '/' + к('подпапка') + '/x.png',
  '/' + к('СНИМКИ') + '/' + к('витрина-390.png'),
  '/' + к('снимки') + '/',
  '/' + к('снимки') + '/' + к('нет-такого.png'),
  '/bot/.env'
];

(async function () {
  await new Promise(function (р) { setTimeout(р, 400); });
  let провалов = 0;
  const проверить = function (да, что) { if (!да) провалов += 1; console.log((да ? '  ок   ' : '  ПРОВАЛ ') + что); };
  console.log(поломка ? '=== ПОЛОМКА: защита заменена наивной склейкой — обязаны быть провалы ===' : '=== Картинки в записях дашборда ===');

  console.log('1. Злые запросы получают отказ');
  for (const адрес of ЗЛЫЕ) {
    const о = await спросить(адрес);
    const отказ = о.код !== 200 && о.тип.indexOf('image/') !== 0;
    проверить(отказ, decodeURIComponent(адрес.replace(/%00/g, '%2500')) + ' → ' + о.код);
  }

  console.log('2. Настоящие картинки отдаются (если лежат на этом компьютере)');
  const jpg = await спросить('/' + к('эталон') + '/' + к('1-витрина.jpg'));
  проверить(jpg.код === 200 && jpg.тип === 'image/jpeg' && jpg.тело[0] === 0xFF && jpg.тело[1] === 0xD8, 'эталон/1-витрина.jpg → ' + jpg.код + ' ' + jpg.тип);
  const png = await спросить('/' + к('снимки') + '/' + к('витрина-стало-390.png'));
  проверить(png.код === 200 && png.тип === 'image/png' && png.тело.slice(0, 4).toString('hex') === '89504e47', 'снимки/витрина-стало-390.png → ' + png.код + ' ' + png.тип);
  const голова = await спросить('/' + к('снимки') + '/' + к('витрина-стало-390.png'), 'HEAD');
  проверить(голова.код === 200 && голова.тело.length === 0, 'HEAD без тела → ' + голова.код);

  console.log('----------------------------------------');
  console.log('провалов: ' + провалов);
  process.exit(поломка ? (провалов > 0 ? 0 : 1) : (провалов ? 1 : 0));
})();
