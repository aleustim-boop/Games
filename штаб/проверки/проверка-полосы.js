/* Верхняя полоса дашборда на подставных данных.

       node штаб/проверки/проверка-полосы.js

   Настоящие штаб/в-работе.json и файлы записей не трогаются вовсе.
   Второй прогон нарочно ломает поиск расхождений — проверка обязана покраснеть. */
'use strict';

const path = require('path');
const ШТАБ = path.join(__dirname, '..');
const живость = require(path.join(ШТАБ, 'живость.js'));
const страница = require(path.join(ШТАБ, 'страница.js'));
const сторож = require(path.join(ШТАБ, 'кто-молчит.js'));

const сейчас = Date.now();
const минутНазад = function (м) { return new Date(сейчас - м * 60000); };

// Подставные записи: исполнители и одна фоновая команда штаба.
const записи = [
  { имя: 'bbbb2222aaaa', изменён: минутНазад(0.5), размер: 5000, исполнитель: true, роль: 'developer', задание: 'живая работа' },
  { имя: 'aaaa1111bbbb', изменён: минутНазад(25), размер: 1000, исполнитель: true, роль: 'designer', задание: 'давно молчит' },
  { имя: 'b9xfon', изменён: минутНазад(0.2), размер: 300, исполнитель: false }
];
const лишнийЖивой = { имя: 'cccc3333dddd', изменён: минутНазад(0.3), размер: 800, исполнитель: true, роль: 'tester', задание: 'работает без записи' };

const пересборкаОк = { идёт: false, последняя: new Date(сейчас - 60000), шаги: [
  { имя: 'списки.js', прошёл: true, строка: 'ок' },
  { имя: 'в-работе.js', прошёл: true, строка: 'ок' },
  { имя: 'важное.js', прошёл: true, строка: 'ок' }
], шагМин: 5 };

const случаи = [
  { имя: 'все работают, лишних нет', работы: [{ что: 'Живая', кто: 'разработчик', задача: 'bbbb2222' }], записи: записи, ждём: 'тихо' },
  { имя: 'в списке молчащий дольше 10 минут', работы: [{ что: 'Живая', кто: 'разработчик', задача: 'bbbb2222' }, { что: 'Молчащая', кто: 'оформитель', задача: 'aaaa1111' }], записи: записи, ждём: 'красно' },
  { имя: 'в списке несуществующая задача', работы: [{ что: 'Призрак', кто: 'никто', задача: 'dead0000' }], записи: записи, ждём: 'красно' },
  { имя: 'работает исполнитель, которого нет в списке', работы: [{ что: 'Живая', кто: 'разработчик', задача: 'bbbb2222' }], записи: записи.concat([лишнийЖивой]), ждём: 'красно' },
  { имя: 'фоновая команда штаба пишет — это не расхождение', работы: [{ что: 'Живая', кто: 'разработчик', задача: 'bbbb2222' }], записи: записи, ждём: 'тихо' },
  { имя: 'пересборка не прошла', работы: [{ что: 'Живая', кто: 'разработчик', задача: 'bbbb2222' }], записи: записи, ждём: 'красно',
    пересборка: { идёт: false, последняя: new Date(сейчас - 60000), шаги: [{ имя: 'важное.js', прошёл: false, строка: 'записи не в порядке' }], шагМин: 5 } },
  { имя: 'пересборка встала 20 минут назад', работы: [{ что: 'Живая', кто: 'разработчик', задача: 'bbbb2222' }], записи: записи, ждём: 'красно',
    пересборка: { идёт: false, последняя: new Date(сейчас - 20 * 60000), шаги: пересборкаОк.шаги, шагМин: 5 } }
];

function прогон(сломать) {
  let провалов = 0;
  for (const с of случаи) {
    const ктоЖив = живость.живостьИсполнителей(сейчас, { записи: с.записи, работы: с.работы });
    const расхождения = сломать
      ? { можноСверить: true, беда: null, список: [], сверено: с.работы.length, безНомера: 0 }
      : живость.расхожденияСписка(ктоЖив);
    const блок = страница.блокСвежесть({ расхождения: расхождения, пересборка: с.пересборка || пересборкаОк, собрано: new Date(сейчас) });
    const красно = блок.indexOf('свежесть--старый') !== -1;
    const тихо = блок.indexOf('class="пересобрано"') !== -1;
    const вышло = красно ? 'красно' : (тихо ? 'тихо' : 'непонятно');
    const ок = вышло === с.ждём;
    if (!ок) провалов += 1;
    console.log((ок ? '  ок   ' : '  ПРОВАЛ ') + с.имя + ': ждали «' + с.ждём + '», вышло «' + вышло + '»');
  }
  return провалов;
}

console.log('1) честный прогон:');
const честно = прогон(false);
console.log('   провалов: ' + честно);

console.log('2) поломка — поиск расхождений всегда молчит:');
const сломано = прогон(true);
console.log('   провалов: ' + сломано + (сломано > 0 ? ' — проверка умеет краснеть' : ' — ПРОВЕРКА СЛЕПА'));

console.log('3) сторож простоя на тех же подставных данных:');
const итог = сторож.собрать(5, false, { записи: записи, работы: [
  { кто: 'разработчик', что: 'Живая', задача: 'bbbb2222' },
  { кто: 'никто', что: 'Призрак', задача: 'dead0000' }
] });
let сторожВерен = true;
for (const с of итог.строки) {
  console.log('   ' + с.кто + ': ' + с.состояние);
  if (с.кто === 'разработчик' && с.состояние !== 'пишет') сторожВерен = false;
  if (с.кто === 'никто' && с.состояние !== 'нет файла') сторожВерен = false;
}
console.log(сторожВерен ? '   ок: живой «пишет», несуществующий — «нет файла»' : '   ПРОВАЛ: сторож ошибся');

process.exitCode = (честно === 0 && сломано > 0 && сторожВерен) ? 0 : 1;
