/* Как поле «подробно» превращает строки ![подпись](путь) в картинки.

       node штаб/проверки/проверка-разметки-снимков.js
*/
'use strict';
const path = require('path');
const важное = require(path.join(__dirname, '..', 'важное-страница.js'));

let провалов = 0;
function проверить(да, что) { if (!да) провалов += 1; console.log((да ? '  ок   ' : '  ПРОВАЛ ') + что); }

const одна = важное.разметить('Было так:\n\n![Витрина стало, 390](снимки/витрина-стало-390.png)\n\nИ дальше текст.');
проверить(/<figure class="снимок">/.test(одна) && /<img src="\/%D1%81%D0%BD%D0%B8%D0%BC%D0%BA%D0%B8\/[^"]+"/.test(одна), 'одна картинка — figure с img по адресу /снимки/…');
проверить(/<figcaption>Витрина стало, 390<\/figcaption>/.test(одна), 'подпись под картинкой');
проверить(/onclick="return открытьСнимок\(this\)"/.test(одна) && /class="снимок-ссылка" href="\//.test(одна), 'по нажатию — крупно (и ссылка на сам файл без скрипта)');

const две = важное.разметить('![макет](эталон/1-витрина.jpg) | ![стало](снимки/витрина-стало-390.png)');
проверить(/<div class="снимки-рядом">/.test(две) && (две.match(/<figure/g) || []).length === 2, 'две через «|» — рядом, в одной обёртке');

for (const путь of ['../bot/.env', 'снимки/../bot/x.png', 'img/витрина/durak.jpg', 'снимки/.env', 'снимки/x.gif', 'снимки/под/x.png', 'C:/Windows/win.ini']) {
  const html = важное.разметить('![злая](' + путь + ')');
  проверить(!/<img/.test(html) && /снимок-нельзя/.test(html), 'не рисуем: ' + путь);
}

const страница = важное.страницаЗаписи({ ключ: 'проба', заголовок: 'Проба', суть: '', подробно: '![a](снимки/витрина-390.png)', кнопки: [], вид: 'к сведению', появилось: null, ответ: null });
проверить(/function открытьСнимок/.test(страница) && /\.снимки-рядом/.test(страница), 'страница записи несёт скрипт крупного просмотра и оформление');

console.log('провалов: ' + провалов);
process.exitCode = провалов ? 1 : 0;
