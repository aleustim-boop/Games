/* ---------------------------------------------------------------------------
   Замок от гонки — тот же приём, что в .claude/hooks/начало-исполнителя.js и
   .claude/hooks/по-окончании-исполнителя.js (см. там подробное объяснение).
   Эта программа тоже читает-правит-пишет штаб/в-работе.json (дописывает
   «начато» старым записям) и запускается из обоих хуков через execFileSync
   почти одновременно с ними — без замка тройка читателей-писателей стирает
   изменения друг друга. --------------------------------------------------- */
function спатьМс(мс) {
  if (!(мс > 0)) return;
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, мс);
}
function взятьЗамок(путьЗамка) {
  if (process.env.ШТАБ_ПРОВЕРКА_БЕЗ_ЗАМКА === '1') return false; // ломающий запуск проверки
  // 29.09: раньше при истечении ТАЙМАУТ_МС функция тихо возвращала false, и
  // правитьJSONСЗамком() писала файл БЕЗ замка — под настоящей нагрузкой
  // обычный прогон сам себе устраивал ту же гонку, что и --сломать (штаб
  // поймал разный счёт двух подряд обычных прогонов). Теперь при истечении
  // таймаута бросаем ошибку — ничего не пишем и не портим, вызывающий код
  // отчитывается в stderr. Таймаут поднят с 5 до 12 секунд — под тестовой
  // нагрузкой в 37 параллельных хуков конкурс за wx-замок мог не уложиться
  // в старые 5 секунд.
  //
  // Второй провал (найден тем же 29.09): УСТАРЕЛ_МС=10000 был МЕНЬШЕ
  // ТАЙМАУТ_МС — на загруженной машине держатель замка мог не пройти ОС-
  // планировщик дольше 10 секунд, ещё не отпустив замок, а ждущий процесс
  // считал его «брошенным» и забирал силой — два процесса писали параллельно
  // без единой ошибки в stderr. Порядок исправлен: силой лок забирается,
  // только когда он старше СОБСТВЕННОГО терпения ТАЙМАУТ_МС (12с) с запасом.
  const УСТАРЕЛ_МС = 30000;
  const ТАЙМАУТ_МС = 12000;
  const начало = Date.now();
  while (true) {
    try {
      fs.closeSync(fs.openSync(путьЗамка, 'wx'));
      return true;
    } catch (о) {
      // 29.09, третья находка: голый примитив на 30 параллельных процессах
      // «потёк» именно тут — fs.openSync(...,'wx') под гонкой на Windows
      // иногда честно кидает EPERM вместо EEXIST, а старый код трактовал
      // любой код кроме EEXIST как «непонятная беда» и тихо писал БЕЗ
      // замка, без единой строки в stderr. EPERM здесь означает то же
      // «файл занят», что и EEXIST, — ждём и пробуем снова. Любой ДРУГОЙ
      // код ошибки — отказ с исключением, не тихая запись без защиты.
      if (о.code !== 'EEXIST' && о.code !== 'EPERM') {
        throw new Error('не удалось создать замок ' + путьЗамка + ': ' + о.message);
      }
      try {
        if (Date.now() - fs.statSync(путьЗамка).mtimeMs > УСТАРЕЛ_МС) {
          try { fs.unlinkSync(путьЗамка); } catch (о2) { /* кто-то уже снял */ }
          continue;
        }
      } catch (о2) { continue; }
      if (Date.now() - начало > ТАЙМАУТ_МС) {
        throw new Error('не дождались замка ' + путьЗамка + ' за ' + ТАЙМАУТ_МС + ' мс — запись отменена, чтобы не писать без защиты');
      }
      спатьМс(15);
    }
  }
}
function отпуститьЗамок(путьЗамка) {
  try { fs.unlinkSync(путьЗамка); } catch (о) { /* уже снят — не беда */ }
}
function тестоваяЗадержка() {
  спатьМс(Number(process.env.ШТАБ_ПРОВЕРКА_ЗАДЕРЖКА_МС || 0));
}
function читатьJSON(файл, поУмолчанию) {
  try { return JSON.parse(fs.readFileSync(файл, 'utf8')); } catch (о) { return поУмолчанию; }
}
function правитьJSONСЗамком(файл, поУмолчанию, менять) {
  const путьЗамка = файл + '.lock';
  const занялЗамок = взятьЗамок(путьЗамка);
  try {
    const данные = читатьJSON(файл, поУмолчанию);
    тестоваяЗадержка();
    менять(данные);
    const временный = файл + '.tmp-' + process.pid + '-' + Date.now();
    fs.writeFileSync(временный, JSON.stringify(данные, null, 2) + '\n', 'utf8');
    fs.renameSync(временный, файл);
  } finally {
    if (занялЗамок) отпуститьЗамок(путьЗамка);
  }
}
/** Дописывает недостающие/старые «начато» прямо в переданном объекте данных. Возвращает true, если что-то поменяла. */
function дописатьНачатоЕслиНадо(данные) {
  const работы = Array.isArray(данные.работы) ? данные.работы : (данные.работы = []);
  let поменяли = false;
  for (const р of работы) {
    if (!р.начато) {
      р.начато = живость.начатоЗаписью(new Date());
      поменяли = true;
    } else if (/^\d{1,2}:\d{2}$/.test(String(р.начато).trim())) {
      const дата = живость.разобратьНачато(р.начато);
      if (дата) {
        р.начато = живость.начатоЗаписью(дата);
        поменяли = true;
      }
    }
  }
  return поменяли;
}
/** Под замком: перечитывает файл заново и, если нужно, дописывает «начато». */
function сохранитьРаботыСЗамком(файл) {
  правитьJSONСЗамком(файл, { работы: [] }, (свежие) => { дописатьНачатоЕслиНадо(свежие); });
}

function сейчас() {
  const д = new Date();
  const дв = (ч) => String(ч).padStart(2, '0');
  return дв(д.getHours()) + ':' + дв(д.getMinutes());
}

const МЕСЯЦЫ = ['января','февраля','марта','апреля','мая','июня',
                'июля','августа','сентября','октября','ноября','декабря'];

function деньСловами(д) {
  return д.getDate() + ' ' + МЕСЯЦЫ[д.getMonth()];
}

function сегодня() {
  return деньСловами(new Date());
}

/** Ячейка «Начато» в таблице: «9 сентября, 23:50» — дата самой работы, не сегодняшняя. */
function начатоСловами(начато) {
  const дата = живость.разобратьНачато(начато);
  if (!дата) return String(начато || '');   // не разобрали — пишем как есть, не выдумывая
  const дв = (ч) => String(ч).padStart(2, '0');
  return деньСловами(дата) + ', ' + дв(дата.getHours()) + ':' + дв(дата.getMinutes());
}

