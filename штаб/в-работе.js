/*
  Переписывает раздел «В работе прямо сейчас» в ЗАДАЧИ.md по файлу
  штаб/в-работе.json — и сам проставляет время из часов машины.

  Зачем отдельная программа. Две беды повторялись раз за разом:

  1. Штаб забывал обновить список после сдач, и владелец видел на дашборде
     давно готовые дела с подписью «идёт 11 часов».
  2. Штаб писал время из головы. Однажды записал начало задач как 03:40,
     когда на часах было 12:20, — выдумал целую ночь работы.

  Обе беды лечатся одинаково: время берётся отсюда, из настоящих часов, а
  список переписывается одной короткой командой:

      node штаб/в-работе.js

  Формат штаб/в-работе.json:

      {
        "работы": [
          { "что": "...", "важность": "горит", "кто": "...", "начато": "12:42" }
        ],
        "заметка": "необязательная строчка под таблицей"
      }

  Поле «начато» необязательно: нет его — программа поставит текущие дату
  и время и впишет обратно в json, чтобы при следующем вызове отсчёт не
  начинался заново. Так «идёт 20 минут» остаётся правдой.

  «Начато» хранит ДАТУ И ВРЕМЯ: «2026-09-10 23:50». Раньше хранилось только
  «23:50», а в таблицу дописывалась сегодняшняя дата — после полуночи
  вчерашняя работа становилась сегодняшней, и «идёт N мин» врало. Старые
  записи «ЧЧ:ММ» программа закрепляет датой при первом же вызове (сегодня,
  а если такое время ещё не наступило — вчера), и дальше они не плывут.
*/

const fs = require('fs');
const path = require('path');
const живость = require('./живость.js');

const корень = path.join(__dirname, '..');
const файлЗадач = path.join(корень, 'ЗАДАЧИ.md');
const файлРабот = path.join(__dirname, 'в-работе.json');

function сейчас() {
  const д = new Date();
  const дв = (ч) => String(ч).padStart(2, '0');
  return дв(д.getHours()) + ':' + дв(д.getMinutes());
}

const МЕСЯЦЫ = ['января','февраля','марта','апреля','мая','июня',
                'июля','августа','сентября','октября','ноября','декабря'];

function деньСловами(д) {
  return д.getDate() + ' ' + МЕСЯЦЫ[д.getMonth()];
}

function сегодня() {
  return деньСловами(new Date());
}

/** Ячейка «Начато» в таблице: «9 сентября, 23:50» — дата самой работы, не сегодняшняя. */
function начатоСловами(начато) {
  const дата = живость.разобратьНачато(начато);
  if (!дата) return String(начато || '');   // не разобрали — пишем как есть, не выдумывая
  const дв = (ч) => String(ч).padStart(2, '0');
  return деньСловами(дата) + ', ' + дв(дата.getHours()) + ':' + дв(дата.getMinutes());
}

if (!fs.existsSync(файлРабот)) {
  console.log('нет файла ' + файлРабот + ' — напишите его и позовите снова');
  process.exit(1);
}

const данные = JSON.parse(fs.readFileSync(файлРабот, 'utf8'));
const работы = данные.работы || [];
let дописали = false;

for (const р of работы) {
  if (!р.начато) {
    р.начато = живость.начатоЗаписью(new Date());
    дописали = true;
  } else if (/^\d{1,2}:\d{2}$/.test(String(р.начато).trim())) {
    // Старая запись без даты: закрепляем её датой сейчас, пока она ещё верна.
    const дата = живость.разобратьНачато(р.начато);
    if (дата) {
      р.начато = живость.начатоЗаписью(дата);
      дописали = true;
    }
  }
}
if (дописали) fs.writeFileSync(файлРабот, JSON.stringify(данные, null, 2) + '\n', 'utf8');

const строки = работы.map(
  (р) => '| ' + р.что + ' | ' + (р.важность === 'потом' || р.важность === 'задел'
      ? р.важность
      : '**' + р.важность + '**') +
    ' | ' + р.кто + ' | ' + начатоСловами(р.начато) + ' |'
);

let раздел =
  '## В работе прямо сейчас\n\n' +
  'Список переписан ' + сегодня() + ', ' + сейчас() +
  ' программой `штаб/в-работе.js`.\nВремя взято из часов машины, а не из головы.\n\n';

if (строки.length === 0) {
  раздел += '**Сейчас не работает никто.** Это либо ошибка штаба — отчёт исполнителя\n' +
            'есть начало следующей работы, а не конец, — либо очередь под эту роль\n' +
            'вправду пуста, и об этом надо сказать владельцу прямо.\n\n';
} else {
  раздел += '| Что | Важность | Кто делает | Начато |\n|---|---|---|---|\n' +
            строки.join('\n') + '\n\n';
}
if (данные.заметка) раздел += данные.заметка + '\n\n';

const текст = fs.readFileSync(файлЗадач, 'utf8');
const начало = текст.indexOf('## В работе прямо сейчас');
if (начало < 0) {
  console.log('в ЗАДАЧИ.md нет раздела «В работе прямо сейчас»');
  process.exit(1);
}
/* Конец раздела — следующий заголовок того же уровня */
const дальше = текст.indexOf('\n## ', начало + 5);
const конец = дальше < 0 ? текст.length : дальше + 1;

fs.writeFileSync(файлЗадач, текст.slice(0, начало) + раздел + текст.slice(конец), 'utf8');
console.log('в работе: ' + работы.length + ', время ' + сейчас());

