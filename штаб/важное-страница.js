const МЕСЯЦЫ_РОД = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
  'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];

/** Год в записях не пишется. Берём год «сейчас», а если вышло будущее — прошлый. */
function сГодом(месяц, день, часы, минуты, сейчас) {
  const год = new Date(сейчас).getFullYear();
  let дата = new Date(год, месяц, день, часы, минуты);
  if (дата.getTime() > сейчас + 60000) дата = new Date(год - 1, месяц, день, часы, минуты);
  return isNaN(дата.getTime()) ? null : дата;
}

/** «10 сентября, 19:16» (поле «появилось») → дата. Не разобрали — null. */
function разобратьПоявилось(текст, сейчас) {
  const н = /(\d{1,2})\s+([а-яё]+),?\s+(\d{1,2}):(\d{2})/i.exec(String(текст || ''));
  if (!н) return null;
  const месяц = МЕСЯЦЫ_РОД.indexOf(н[2].toLowerCase());
  if (месяц < 0) return null;
  return сГодом(месяц, Number(н[1]), Number(н[3]), Number(н[4]), сейчас);
}

/** «10.09, 19:13» (прочитано.json) → дата. Не разобрали — null. */
function разобратьОткрыто(текст, сейчас) {
  const н = /(\d{1,2})\.(\d{1,2}),?\s+(\d{1,2}):(\d{2})/.exec(String(текст || ''));
  if (!н) return null;
  return сГодом(Number(н[2]) - 1, Number(н[1]), Number(н[3]), Number(н[4]), сейчас);
}

/** Время ответа владельца — точное, из «когда точно». Нет его — null. */
function времяОтвета(запись) {
  if (!запись.ответ || !запись.ответ['когда точно']) return null;
  const дата = new Date(запись.ответ['когда точно']);
  return isNaN(дата.getTime()) ? null : дата;
}

/** Моложе ли суток. Единственное место, где меряются сутки. */
function свежееСуток(дата, сейчас) {
  if (!дата) return false;
  return сейчас - дата.getTime() < СУТКИ_МС;
}

/** «19:50», а если не сегодня — «9 сентября, 19:50». */
function словаВремени(дата, сейчас) {
  const дв = function (ч) { return String(ч).padStart(2, '0'); };
  const часы = дв(дата.getHours()) + ':' + дв(дата.getMinutes());
  const тогда = new Date(сейчас);
  const сегодня = дата.getFullYear() === тогда.getFullYear() && дата.getMonth() === тогда.getMonth()
    && дата.getDate() === тогда.getDate();
  return сегодня ? часы : дата.getDate() + ' ' + МЕСЯЦЫ_РОД[дата.getMonth()] + ', ' + часы;
}

/** Время правки файла записей: верхняя граница, когда что-то в нём решили. */
