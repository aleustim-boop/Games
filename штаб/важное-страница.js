const ПАПКИ_СНИМКОВ = ['снимки', 'эталон'];

/**
 * «снимки/витрина-390.png» → { папка, имя }; всё прочее — null.
 * Косая в начале допустима: так путь приходит из адреса запроса.
 */
function разобратьПутьСнимка(путь) {
  const текст = String(путь || '').trim().replace(/^\//, '');
  const н = /^([^/\\]+)\/([^/\\]+)$/.exec(текст);
  if (!н) return null;
  const папка = н[1];
  const имя = н[2];
  if (ПАПКИ_СНИМКОВ.indexOf(папка) === -1) return null;
  if (имя.indexOf('..') !== -1 || имя.charAt(0) === '.') return null;
  if (!/^[\p{L}\p{N}_. -]+\.(png|jpe?g)$/iu.test(имя)) return null;
  return { папка: папка, имя: имя };
}

/** Одна картинка: во всю ширину, подпись под ней, по нажатию — крупно. */
function разметкаСнимка(подпись, путь) {
  const разбор = разобратьПутьСнимка(путь);
  if (!разбор) {
    return '<p class="снимок-нельзя">Картинка «' + э(подпись || путь) + '» не показана: брать их можно только '
      + 'из папок снимки/ и эталон/ проекта, файлы png или jpg.</p>';
  }
  const адрес = '/' + encodeURIComponent(разбор.папка) + '/' + encodeURIComponent(разбор.имя);
  return '<figure class="снимок">'
    + '<a class="снимок-ссылка" href="' + адрес + '" onclick="return открытьСнимок(this)">'
    + '<img src="' + адрес + '" alt="' + э(подпись) + '" loading="lazy"></a>'
    + (подпись ? '<figcaption>' + э(подпись) + '</figcaption>' : '')
    + '</figure>';
}

/* Строка из одних картинок: ![подпись](путь), можно несколько через «|». */
const СТРОКА_СНИМКОВ = /^!\[[^\]]*\]\([^)]*\)(\s*\|\s*!\[[^\]]*\]\([^)]*\))*$/;

function разметкаСтрокиСнимков(строка) {
  const снимки = [];
  const образец = /!\[([^\]]*)\]\(([^)]*)\)/g;
  let н;
  while ((н = образец.exec(строка))) снимки.push(разметкаСнимка(н[1].trim(), н[2].trim()));
  if (снимки.length === 1) return снимки[0];
  // Две и больше — рядом; на узком экране встают друг под другом (см. оформление ниже).
  return '<div class="снимки-рядом">' + снимки.join('') + '</div>';
}

