/* Раздел «Важное»: список заголовков и страница каждой записи.

   Зачем. Владелец написал: «всю важную информацию, вопросы и другое пиши мне
   в дашборд, потому как тут в ленте вся важная инфо улетает; такой некий
   заголовок, и чтобы я открывал его в отдельной странице, и там коротко
   о важном было описано — суть вопроса или инфо».

   Из этого три правила, и они здесь главнее красоты:

   1. ЗАГОЛОВОК ПОНЯТЕН БЕЗ ОТКРЫТИЯ. Не «вопрос по рейтингу», а «рейтинг
      силы движется слишком медленно?». Один взгляд — и ясно, о чём речь и
      ждут ли от тебя ответа.

   2. КОРОТКО. Внутри — в чём дело, что предлагаем, что нужно от него.
      Не пересказ нашей работы.

   3. НОВОЕ ВИДНО СРАЗУ, а список не растёт без предела. Иначе получится
      второй поток вместо переписки — то есть хуже, чем было.

   Записи ведёт штаб в штаб/важное.json. Эта половина только показывает. */

'use strict';

const fs = require('fs');
const path = require('path');
const страница = require('./страница.js');

const ФАЙЛ_ЗАПИСЕЙ = path.join(__dirname, 'важное.json');
const ФАЙЛ_ПРОЧИТАННОГО = path.join(__dirname, 'прочитано.json');
const ФАЙЛ_ОТВЕТОВ = path.join(__dirname, 'ответы.json');

/* Сколько записей показываем на главной, пока не нажали «показать всё».
   Список длиннее человек не читает — он его пролистывает, а это то же
   самое, что не показать вовсе. */
const НА_ГЛАВНОЙ = 3;

const ВИДЫ = {
  'нужен ответ': { порядок: 0, метка: 'нужен ответ', класс: 'важное--ответ' },
  'к сведению': { порядок: 1, метка: 'к сведению', класс: 'важное--сведение' },
  'решено': { порядок: 2, метка: 'решено', класс: 'важное--решено' }
};

function э(текст) {
  return String(текст === null || текст === undefined ? '' : текст)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;')
    .replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

/* ---------------------------------------------------------------------------
   Чтение с диска
--------------------------------------------------------------------------- */

/** Записи штаба. Не прочитались — честно говорим, а не показываем пустоту. */
function прочитатьЗаписи() {
  let текст;
  try {
    текст = fs.readFileSync(ФАЙЛ_ЗАПИСЕЙ, 'utf8');
  } catch (ошибка) {
    return { записи: [], беда: 'файла штаб/важное.json нет — раздел «Важное» показывать нечем' };
  }
  try {
    const данные = JSON.parse(текст);
    const записи = Array.isArray(данные.записи) ? данные.записи : [];
    return { записи: записи, беда: null };
  } catch (ошибка) {
    return { записи: [], беда: 'в штаб/важное.json сломана разметка: ' + ошибка.message };
  }
}

/** Что владелец уже открывал. */
function прочитанное() {
  try {
    const данные = JSON.parse(fs.readFileSync(ФАЙЛ_ПРОЧИТАННОГО, 'utf8'));
    return данные && данные.открыто ? данные.открыто : {};
  } catch (ошибка) {
    return {};
  }
}

/** Ответы владельца — по ключу записи. */
function ответы() {
  try {
    const данные = JSON.parse(fs.readFileSync(ФАЙЛ_ОТВЕТОВ, 'utf8'));
    return данные && данные.ответы ? данные.ответы : {};
  } catch (ошибка) {
    return {};
  }
}

/**
 * Готовый список записей: разобранный, отсортированный, с пометками
 * «новое» и «вы ответили».
 */
function собратьСписок() {
  const прочитано = прочитатьЗаписи();
  const открыто = прочитанное();
  const отвечено = ответы();

  const записи = прочитано.записи.map(function (з) {
    const вид = ВИДЫ[з.вид] ? з.вид : 'к сведению';
    return {
      ключ: String(з.ключ || ''),
      заголовок: з.заголовок || '(без заголовка)',
      суть: з.суть || '',
      подробно: з.подробно || '',
      особая: з.особая || null,
      кнопки: Array.isArray(з.кнопки) ? з.кнопки : [],
      вид: вид,
      порядок: ВИДЫ[вид].порядок,
      появилось: з.появилось || null,
      новое: !открыто[String(з.ключ || '')],
      ответ: отвечено[String(з.ключ || '')] || null
    };
  });

  // Сначала то, где ждут решения; решённое — в конец. Внутри вида новое выше.
  записи.sort(function (а, б) {
    if (а.порядок !== б.порядок) return а.порядок - б.порядок;
    if (а.новое !== б.новое) return а.новое ? -1 : 1;
    return 0;
  });

  return { записи: записи, беда: прочитано.беда };
}

/** Одна запись по ключу. Нет такой — null. */
function найтиЗапись(ключ) {
  const список = собратьСписок().записи;
  for (const з of список) if (з.ключ === ключ) return з;
  return null;
}

/* ---------------------------------------------------------------------------
   Простая разметка для поля «подробно»
--------------------------------------------------------------------------- */

/**
 * Штаб пишет текст по-человечески, а не тегами. Понимаем немного:
 * пустая строка — новый абзац, строка с «- » — пункт списка,
 * «## » — подзаголовок, **жирный** — выделение.
 * Всё остальное обезвреживается, поэтому в записи можно писать что угодно.
 */
function разметить(текст) {
  const строки = String(текст || '').split(/\r?\n/);
  let куски = '';
  let вСписке = false;

  for (const строка of строки) {
    const обрезок = строка.trim();

    if (!обрезок) {
      if (вСписке) { куски += '</ul>'; вСписке = false; }
      continue;
    }

    if (обрезок.startsWith('## ')) {
      if (вСписке) { куски += '</ul>'; вСписке = false; }
      куски += '<h2>' + жирный(обрезок.slice(3)) + '</h2>';
      continue;
    }

    if (обрезок.startsWith('- ')) {
      if (!вСписке) { куски += '<ul>'; вСписке = true; }
      куски += '<li>' + жирный(обрезок.slice(2)) + '</li>';
      continue;
    }

    if (вСписке) { куски += '</ul>'; вСписке = false; }
    куски += '<p>' + жирный(обрезок) + '</p>';
  }

  if (вСписке) куски += '</ul>';
  return куски;
}

/** **Так** становится жирным. Текст при этом обезврежен. */
function жирный(текст) {
  return э(текст).replace(/\*\*([^*]+)\*\*/g, '<b>$1</b>');
}

