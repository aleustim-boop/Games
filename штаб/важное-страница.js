/* Раздел «Важное»: список заголовков и страница каждой записи.

   Зачем. Владелец написал: «всю важную информацию, вопросы и другое пиши мне
   в дашборд, потому как тут в ленте вся важная инфо улетает; такой некий
   заголовок, и чтобы я открывал его в отдельной странице, и там коротко
   о важном было описано — суть вопроса или инфо».

   Из этого три правила, и они здесь главнее красоты:

   1. ЗАГОЛОВОК ПОНЯТЕН БЕЗ ОТКРЫТИЯ. Не «вопрос по рейтингу», а «рейтинг
      силы движется слишком медленно?». Один взгляд — и ясно, о чём речь и
      ждут ли от тебя ответа.

   2. КОРОТКО. Внутри — в чём дело, что предлагаем, что нужно от него.
      Не пересказ нашей работы.

   3. НОВОЕ ВИДНО СРАЗУ, а список не растёт без предела. Иначе получится
      второй поток вместо переписки — то есть хуже, чем было.

   Записи ведёт штаб в штаб/важное.json. Эта половина только показывает. */

'use strict';

