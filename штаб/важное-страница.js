/* ---------------------------------------------------------------------------
   Список на главной и целая страница списка
--------------------------------------------------------------------------- */

function однаСтрока(з) {
  const вид = ВИДЫ[з.вид];
  const новое = з.новое && з.вид !== 'решено' ? '<span class="важное-новое">новое</span>' : '';
  const когда = з.появилось ? '<span class="важное-когда">' + э(з.появилось) + '</span>' : '';
  const ответДан = з.ответ
    ? '<span class="важное-ответ-дан">вы ответили: ' + э(з.ответ.имя || з.ответ.кнопка) + '</span>'
    : '';

  return '<li class="' + вид.класс + '">'
    + '<a class="запись" href="/важное/' + encodeURIComponent(з.ключ) + '">'
    + '<div class="важное-верх">'
    + '<span class="важное-вид">' + э(вид.метка) + '</span>' + новое + когда
    + '</div>'
    + '<div class="важное-заголовок">' + э(з.заголовок) + '</div>'
    + (з.суть ? '<div class="важное-суть">' + э(з.суть) + '</div>' : '')
    + ответДан
    + '</a></li>';
}

/**
 * Блок для главной страницы дашборда.
 * Показываем немного: ждущее ответа целиком, остального по три, решённое —
 * одной строкой. Всё остальное — за ссылкой «показать всё».
 */
function блокДляГлавной() {
  const собрано = собратьСписок();

  if (собрано.беда) {
    return '<section><h2>Важное</h2><p class="пояснение">' + э(собрано.беда) + '</p></section>';
  }
  if (!собрано.записи.length) return '';

  const ждутОтвета = собрано.записи.filter(function (з) { return з.вид === 'нужен ответ'; });
  const кСведению = собрано.записи.filter(function (з) { return з.вид === 'к сведению'; });
  const решено = собрано.записи.filter(function (з) { return з.вид === 'решено'; });
  const новых = собрано.записи.filter(function (з) { return з.новое && з.вид !== 'решено'; }).length;

  const показать = ждутОтвета.concat(кСведению.slice(0, НА_ГЛАВНОЙ));
  const спрятано = кСведению.length - Math.min(кСведению.length, НА_ГЛАВНОЙ) + решено.length;

  let строки = '';
  for (const з of показать) строки += однаСтрока(з);

  const ещё = спрятано > 0
    ? '<a class="важное-ещё" href="/важное">Показать всё: ещё ' + спрятано
      + (решено.length ? ' (из них решённых: ' + решено.length + ')' : '') + ' →</a>'
    : '';

  const счёт = новых
    ? '<span class="счёт">' + новых + ' новых</span>'
    : '<span class="счёт">всё прочитано</span>';

  return `
  <section>
    <h2>Важное ${счёт}</h2>
    <p class="пояснение">Здесь всё, что не должно потеряться в переписке: вопросы к вам и то, что стоит знать. Заголовок открывается в свою страницу, там коротко. Красная метка — вы это ещё не открывали.</p>
    <ul class="важное">${строки}</ul>
    ${ещё}
  </section>`;
}

/** Целая страница со всеми записями — за ссылкой «показать всё». */
function страницаСписка() {
  const собрано = собратьСписок();
  let строки = '';
  for (const з of собрано.записи) строки += однаСтрока(з);

  return обёртка('Важное — всё', `
    <a class="назад" href="/">← к дашборду</a>
    <h1>Важное: все записи</h1>
    <p>Сверху то, где ждут вашего решения. Ниже — то, что просто стоит знать. В конце решённое: оно не пропадает, чтобы всегда было видно, чем кончилось.</p>
    ${собрано.беда ? '<p>' + э(собрано.беда) + '</p>' : ''}
    <ul class="важное">${строки}</ul>`);
}

/* ---------------------------------------------------------------------------
   Страница одной записи
--------------------------------------------------------------------------- */

function страницаЗаписи(запись, особоеНутро) {
  const вид = ВИДЫ[запись.вид];

  let кнопки = '';
  if (запись.кнопки.length) {
    if (запись.ответ) {
      кнопки += '<div class="принято"><p><b>Принято: ' + э(запись.ответ.имя || запись.ответ.кнопка) + '</b><br>'
        + 'Записано ' + э(запись.ответ.когда || '') + '. Можно нажать другое — запишется новое.</p></div>';
    } else {
      кнопки += '<h2>Что скажете</h2><p>Нажмите один раз — этого достаточно, писать ничего не нужно.</p>';
    }
    кнопки += '<div class="кнопки-ответа">';
    for (const к of запись.кнопки) {
      кнопки += '<a class="кнопка-ответа" href="/ответ?запись=' + encodeURIComponent(запись.ключ)
        + '&кнопка=' + encodeURIComponent(к.ключ) + '">' + э(к.имя)
        + (к.пояснение ? '<span>' + э(к.пояснение) + '</span>' : '') + '</a>';
    }
    кнопки += '</div>';
    кнопки += '<p style="font-size:14.5px;color:var(--muted)">Ничего не подходит — напишите словами, это тоже ответ.</p>';
  }

  const нутро = особоеНутро || разметить(запись.подробно);

  return обёртка(запись.заголовок, `
    <a class="назад" href="/">← к дашборду</a>
    <div class="важное-верх">
      <span class="важное-вид">${э(вид.метка)}</span>
      ${запись.появилось ? '<span class="важное-когда">' + э(запись.появилось) + '</span>' : ''}
    </div>
    <h1>${э(запись.заголовок)}</h1>
    ${запись.суть ? '<div class="запись-суть">' + э(запись.суть) + '</div>' : ''}
    ${нутро}
    ${кнопки}`, вид.класс);
}

/** Страница «принято» после нажатия кнопки ответа. */
function страницаПринято(запись, кнопка) {
  return обёртка('Принято', `
    <div class="принято"><p><b>Принято: ${э(кнопка ? (кнопка.имя || кнопка.ключ) : 'ответ')}</b><br>
    Штаб увидит это сам, писать ничего не нужно.</p></div>
    <a class="назад" href="/важное/${encodeURIComponent(запись.ключ)}">← вернуться к записи</a><br>
    <a class="назад" href="/">← к дашборду</a>`);
}

/** Страница «такой записи нет» — на случай старой ссылки. */
function страницаНеНашлась() {
  return обёртка('Записи нет', `
    <h1>Такой записи нет</h1>
    <p>Возможно, ссылка старая или запись переименовали. Все записи целиком — на странице ниже.</p>
    <a class="назад" href="/важное">← все записи</a><br>
    <a class="назад" href="/">← к дашборду</a>`);
}

function обёртка(заголовок, нутро, класс) {
  return `<!doctype html>
<html lang="ru">
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${э(заголовок)}</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Alegreya:wght@500;700;800&family=Alegreya+Sans:wght@400;500;700&family=JetBrains+Mono:wght@400;700&display=swap">
<style>${страница.ОФОРМЛЕНИЕ}</style>
<div class="лист запись-лист ${класс || ''}">${нутро}</div>
</html>`;
}

