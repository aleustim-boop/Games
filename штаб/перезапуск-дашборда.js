/*
  Перезапуск дашборда штаба одной командой.

      node штаб/перезапуск-дашборда.js          (порт 8791)
      node штаб/перезапуск-дашборда.js 8799     (другой порт)

  Зачем отдельная программа — та же причина, что у штаб/перезапуск-сервера.js:
  найти, кто занял порт, снять его, поднять заново и проверить — это три-четыре
  команды, и каждая у владельца всплывает окном «разрешить?». Одна короткая
  команда спрашивает один раз.

  ТУННЕЛЬ НЕ ТРОГАЕМ. Он смотрит на порт 8791, а не на сам процесс: пока
  дашборд снова слушает тот же порт, адрес у владельца остаётся прежним.

  ДВЕ СТРАХОВКИ (замечание ревьюера):
    1. Снимаем только дашборд. Прежде чем снять процесс на порту, читаем его
       строку запуска: в ней обязан быть «дашборд.js». Иначе опечатка в порту
       (8790 вместо 8791) молча сняла бы сервер комнат — и игра вдвоём
       легла бы у всех посреди партии.
    2. «Отвечает 200» — ещё не «запустился новый». Если старый процесс не
       снялся, новый не встанет на порт, а на вопрос ответит старый. Поэтому
       после ответа сверяем, что порт держит именно новый процесс.
*/

'use strict';

const { execFileSync, spawn } = require('child_process');
const fs = require('fs');
const http = require('http');
const path = require('path');

const корень = path.join(__dirname, '..');
const журнал = path.join(__dirname, 'дашборд.log');

// Первая страница собирает всё сразу: git, службы, сайт на github.io.
// Поэтому ждём ответа терпеливо, но не бесконечно.
const ПОПЫТОК = 20;
const ПАУЗА_МС = 1500;
const СРОК_ОТВЕТА_МС = 15000;

/* Кто сейчас слушает порт. Пусто — значит никто, и это не беда. */
function ктоНаПорту(номерПорта) {
  try {
    const вывод = execFileSync('netstat', ['-ano', '-p', 'TCP'], { encoding: 'utf8' });
    const номера = new Set();
    for (const строка of вывод.split('\n')) {
      /* Только слушающий сокет: строки с чужими подключениями к нам
         содержат тот же порт, но снимать по ним нельзя — это не дашборд. */
      if (!/LISTENING/i.test(строка)) continue;
      const части = строка.trim().split(/\s+/);
      const адрес = части[1] || '';
      if (!адрес.endsWith(':' + номерПорта)) continue;
      const номер = части[части.length - 1];
      if (/^\d+$/.test(номер) && номер !== '0') номера.add(номер);
    }
    return [...номера];
  } catch (ошибка) {
    return [];
  }
}

/**
 * Строка запуска процесса — как её видит система. Не узнали — null.
 * Спрашиваем PowerShell (так же, как штаб/сбор.js ищет бота и туннель), но
 * просим ответ в base64: кириллица в пути («штаб\дашборд.js») иначе
 * портится кодировкой консоли, и сверка по ней молча не срабатывала бы.
 */
function строкаЗапуска(номер) {
  if (!/^\d+$/.test(String(номер))) return null;
  const запрос = '$п = Get-CimInstance Win32_Process -Filter "ProcessId=' + номер + '"; '
    + 'if ($п -and $п.CommandLine) { [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($п.CommandLine)) }';
  try {
    const вывод = execFileSync('powershell', ['-NoProfile', '-NonInteractive', '-Command', запрос],
      { encoding: 'utf8', timeout: 15000 }).trim();
    if (!вывод) return null;
    return Buffer.from(вывод, 'base64').toString('utf8');
  } catch (ошибка) {
    return null;
  }
}

/**
 * Это наш дашборд? Узнаём по программе в строке запуска: «штаб\дашборд.js»
 * (или через «/») отдельным словом — полным путём, как его поднимает эта
 * программа, или «штаб/дашборд.js», как его поднимает штаб руками.
 * Просто «дашборд.js» где-то в строке — мало: так совпала бы и любая
 * «…-не-дашборд.js», проверка поймала это на своей же пустышке.
 */
function этоДашборд(строка) {
  return typeof строка === 'string' && /(^|[\s"'\\/])штаб[\\/]дашборд\.js(?=["'\s]|$)/i.test(строка);
}

/**
 * Снять старый дашборд. Чужой процесс на порту не трогаем вовсе.
 * Вернёт { можноДальше, слова }.
 */
function снятьСтарый(порт, снять) {
  const занявшие = ктоНаПорту(порт);
  if (!занявшие.length) return { можноДальше: true, слова: ['порт ' + порт + ' был свободен'] };
  const слова = [];
  for (const номер of занявшие) {
    const строка = строкаЗапуска(номер);
    if (строка === null) {
      return { можноДальше: false, слова: слова.concat(['порт ' + порт + ' держит процесс ' + номер
        + ', но узнать, что это за программа, не вышло — снимать вслепую не стану']) };
    }
    if (!этоДашборд(строка)) {
      return { можноДальше: false, слова: слова.concat(['порт ' + порт + ' держит НЕ дашборд (процесс ' + номер
        + ': ' + строка.slice(0, 120) + ') — не трогаю. Проверьте номер порта']) };
    }
    слова.push(снять(номер) ? 'снял старый дашборд, номер процесса ' + номер
      : 'не смог снять процесс ' + номер + ' — возможно, он уже закрылся');
  }
  return { можноДальше: true, слова: слова };
}

function снятьПоНомеру(номер) {
  try {
    execFileSync('taskkill', ['/PID', String(номер), '/F'], { stdio: 'ignore' });
    return true;
  } catch (ошибка) {
    return false;
  }
}

/* Поднимаем заново, отвязав от этой программы: дашборд должен её пережить. */
function поднятьНовый(порт) {
  const поток = fs.openSync(журнал, 'a');
  const дитя = spawn(process.execPath, [path.join(__dirname, 'дашборд.js'), String(порт)], {
    cwd: корень,
    detached: true,
    windowsHide: true,
    stdio: ['ignore', поток, поток]
  });
  дитя.unref();
  return дитя.pid;
}

/* Один запрос к главной. Отвечает кодом ответа или 0, если не ответил. */
function спросить(порт) {
  return new Promise(function (готово) {
    const запрос = http.get('http://127.0.0.1:' + порт + '/', { timeout: СРОК_ОТВЕТА_МС }, function (ответ) {
      ответ.resume();
      ответ.on('end', function () { готово(ответ.statusCode); });
    });
    запрос.on('timeout', function () { запрос.destroy(); });
    запрос.on('error', function () { готово(0); });
  });
}

/** Держит ли порт именно этот процесс. */
function портДержит(порт, номер) {
  return ктоНаПорту(порт).indexOf(String(номер)) !== -1;
}

/**
 * Весь перезапуск. «настройки» — только для проверок: снять(номер) вместо
 * настоящего снятия, попыток/паузу поменьше.
 * Вернёт { ок, слова }.
 */
async function перезапустить(порт, настройки) {
  const н = настройки || {};
  const слова = [];
  const снятие = снятьСтарый(порт, н.снять || снятьПоНомеру);
  слова.push.apply(слова, снятие.слова);
  if (!снятие.можноДальше) return { ок: false, слова: слова };

  // Даём системе отпустить порт, иначе новый процесс может не встать на него.
  await new Promise(function (р) { setTimeout(р, н.пауза || 700); });
  const новый = поднятьНовый(порт);
  слова.push('поднял новый дашборд, номер процесса ' + новый + ', журнал: штаб/дашборд.log');

  let последний = 0;
  for (let попытка = 1; попытка <= (н.попыток || ПОПЫТОК); попытка++) {
    await new Promise(function (р) { setTimeout(р, ПАУЗА_МС); });
    последний = await спросить(порт);
    if (последний !== 200) continue;
    if (!портДержит(порт, новый)) {
      const держит = ктоНаПорту(порт).join(', ') || 'никто';
      слова.push('на вопрос ответили 200, но порт держит НЕ новый процесс (держит: ' + держит
        + ') — старый не снялся, новый не встал. Смотрите штаб/дашборд.log');
      return { ок: false, слова: слова, новый: новый };
    }
    слова.push('дашборд отвечает 200, порт держит новый процесс ' + новый + ': http://127.0.0.1:' + порт + '/');
    return { ок: true, слова: слова, новый: новый };
  }
  слова.push('дашборд НЕ отвечает 200 (последний ответ: ' + (последний || 'нет связи') + ') — смотрите штаб/дашборд.log');
  return { ок: false, слова: слова, новый: новый };
}

if (require.main === module) {
  перезапустить(process.argv[2] || '8791').then(function (итог) {
    for (const с of итог.слова) console.log(с);
    if (!итог.ок) process.exitCode = 1;
  });
}

module.exports = {
  перезапустить: перезапустить,
  ктоНаПорту: ктоНаПорту,
  строкаЗапуска: строкаЗапуска,
  этоДашборд: этоДашборд,
  портДержит: портДержит
};
