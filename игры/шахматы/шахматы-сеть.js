'use strict';

/* =====================================================================
   ШАХМАТЫ ПО СЕТИ — МОСТ МЕЖДУ ДОСКОЙ И ОБЩИМ ФАЙЛОМ СВЯЗИ.

   Разговор с сервером ведёт общее/js/сеть.js — один файл на все сетевые игры.
   Он знает про коды комнат, пропуска и длинный опрос; про шахматы он не
   знает ничего. Доску рисует игры/шахматы/шахматы-экран.js — она не знает ничего
   про сеть. Между ними и стоит этот файл, и в нём нет ни правил игры,
   ни запросов к серверу.

   Двери наружу — те же, что у дурака и шашек (общее/js/сеть.js зовёт их не
   глядя, в какую игру играют):

       window.ИграПоСети = { начать, показатьВид, показатьСвязь,
                             экран, вМеню, назадСоВхода, идёт }

   Обратно, от доски к серверу, через отправителя, переданного в
   ШахматыЭкран.включитьСеть, уходит один вид сообщения — обычный ход:

       { действие: 'ход', откуда, куда, превращение? }

   Ровно то, что принимает «сделатьХод» в server/игры/шахматы.js.
   «превращение» добавляется в письмо, только когда доска его прислала
   (пешка дошла до края и человек выбрал фигуру) — сервер сам отказывает,
   если поле лишнее там, где превращения нет. Сдачу и ничью по сети
   доска шлёт САМА, напрямую через window.Сеть.отправитьХод({действие:
   'сдаться'|'ничья'|'ничья-да'|'ничья-нет'}) — эти письма не ходят
   через отправителя из этого моста, он занят только обычными ходами.

   ЧЕМ ЭТОТ МОСТ ОТЛИЧАЕТСЯ ОТ ШАШЕЧНОГО. У шашек показ экранов «с кем
   играть» и сама доска — разные объекты (window.ШашкиРежимы и
   window.ШашкиЭкран), поэтому там два разных «места». У шахмат одна
   дверь наружу — window.ШахматыЭкран — отвечает и за доску
   (включитьСеть/выключитьСеть/показатьСетевойВид), и за переключение
   экранов лобби/доски (показатьПоИмени): так решено заданием на этап,
   и игры/шахматы/шахматы-лобби.js на неё уже рассчитывает. Поэтому здесь одна
   функция доска() вместо пары доска()+режимы().

   ПОЧЕМУ МОСТ ПОДКЛЮЧАЕТСЯ РАНЬШЕ общее/js/сеть.js. Тот в конце своего файла
   сразу берётся за дело и может немедленно открыть экран — например,
   когда человек пришёл по ссылке-приглашению. Зовёт он для этого мост.
   Не будь моста к той секунде, приглашение открыло бы пустоту.
   ===================================================================== */

(function () {
  /* Имена экранов, которыми говорит общее/js/сеть.js, — дураковы. У шахмат
     «экран-меню» — это лобби («с кем играть»), «экран-игры» — доска.
     Остальные имена (экран-друга, экран-комнаты, экран-входа и т.п.)
     совпадают с разметкой шахмат.html как есть — их не переводим. */
  var ПЕРЕВОД_ЭКРАНОВ = {
    'экран-меню': 'экран-лобби',
    'экран-игры': 'экран-шахмат'
  };

  /* Идёт ли сейчас партия по сети. Спрашивают и общее/js/сеть.js, и доска. */
  var вПартии = false;

  /** Доска (и она же — навигация по экранам). Появляется в конце
   *  страницы, поэтому спрашиваем каждый раз, а не запоминаем один раз. */
  function доска() {
    return window.ШахматыЭкран || null;
  }

  /** Полный файл связи (не путать с огрызком, который кладёт «похвастаться»). */
  function связь() {
    var сеть = window.Сеть;
    return сеть && typeof сеть.отправитьХод === 'function' ? сеть : null;
  }

  /* -------------------------------------------------------------------
     Что зовёт общее/js/сеть.js
     ------------------------------------------------------------------- */

  /** За стол сели двое — партия пошла. Показываем доску заранее, ещё
   *  до первого «вида»: иначе человек секунду смотрит на лобби. */
  function начать() {
    вПартии = true;
    var экранДоски = доска();
    if (!экранДоски) return;
    экранДоски.включитьСеть(отправитьХод);
    if (typeof экранДоски.показатьПоИмени === 'function') {
      экранДоски.показатьПоИмени('экран-шахмат');
    }
  }

  /**
   * Новое состояние стола. Всё, что здесь делается, — передаём доске:
   * решать, что нарисовать и как показать чужой ход, — её работа.
   */
  function показатьВид(вид) {
    if (!вид) return;
    вПартии = true;
    var экранДоски = доска();
    if (!экранДоски) return;
    экранДоски.включитьСеть(отправитьХод);   // повторный вызов ничего не портит
    экранДоски.показатьСетевойВид(вид);
    передатьЗнаки(вид);
  }

  /**
   * Строка над доской: жив ли друг и жива ли связь. Слова приходят готовые
   * из общее/js/сеть.js, вид — 'тревога', 'ожидание' или пусто. Пустой текст
   * прячет строку целиком.
   */
  function показатьСвязь(текст, вид) {
    var строка = document.getElementById('строка-связи');
    if (!строка) return;
    строка.textContent = текст || '';
    строка.classList.toggle('скрыт', !текст);
    строка.classList.toggle('связь--тревога', вид === 'тревога');
    строка.classList.toggle('связь--ожидание', вид === 'ожидание');
  }

  /** Сеть просит показать экран. Имена переводим на свои. */
  function экран(имя) {
    var экранДоски = доска();
    if (!экранДоски || typeof экранДоски.показатьПоИмени !== 'function') return;
    var наш = ПЕРЕВОД_ЭКРАНОВ[имя] || имя;
    /* Уходим с доски — значит, сетевая партия для нас кончилась: дальше
       человек или сидит в комнате, или выбирает соперника заново. */
    if (наш !== 'экран-шахмат') отпуститьДоску();
    экранДоски.показатьПоИмени(наш);
  }

  /** Сеть закрыла партию (комната пропала, вышли сами). */
  function вМеню() {
    отпуститьДоску();
    var экранДоски = доска();
    if (экранДоски && typeof экранДоски.показатьПоИмени === 'function') {
      экранДоски.показатьПоИмени('экран-лобби');
    }
  }

  /**
   * «Назад» с экрана «Вход по коду» (общее/js/сеть.js, назадСоВхода). Вход по
   * коду открывается только из лобби строкой «Есть код? Войти», поэтому
   * и назад — снова в лобби. До входа в комнату сетевой партии ещё нет —
   * отпуститьДоску() здесь для симметрии с вМеню() и на случай, если вход
   * открыли не с чистого места.
   */
  function назадСоВхода() {
    отпуститьДоску();
    var экранДоски = доска();
    if (экранДоски && typeof экранДоски.показатьПоИмени === 'function') {
      экранДоски.показатьПоИмени('экран-лобби');
    }
  }

  /** Вернуть доску в обычное состояние: дальше играем с ботом или вдвоём. */
  function отпуститьДоску() {
    if (!вПартии) return;
    вПартии = false;
    показатьСвязь('');
    освежитьКнопкуЗнаков(null);
    var экранДоски = доска();
    if (экранДоски) экранДоски.выключитьСеть();
  }

  /* -------------------------------------------------------------------
     Что зовёт доска
     ------------------------------------------------------------------- */

  /**
   * Отправить обычный ход соперника по сети. Обещание никогда не срывается:
   * при любой беде вернётся отказ с причиной, которую доска покажет
   * человеку словами. Поля перечислены поимённо — лишнего серверу не
   * отправляем, «превращение» добавляем, только если доска его прислала.
   */
  function отправитьХод(ход) {
    var сеть = связь();
    if (!сеть) {
      return Promise.resolve({
        принято: false,
        причина: 'Игра по сети не загрузилась — обновите страницу'
      });
    }
    var сообщение = {
      действие: 'ход',
      откуда: ход.откуда,
      куда: ход.куда
    };
    if (ход.превращение) сообщение.превращение = ход.превращение;
    return сеть.отправитьХод(сообщение).then(function (ответ) {
      /* Пустой ответ приходит, когда человек успел выйти из партии:
         тогда показывать нечего, и молчание тут — правильный ответ. */
      if (!ответ) return { принято: false, тихо: true };
      if (ответ.ошибкаСвязи) {
        return { принято: false, причина: 'Связь с игрой потеряна — ход не ушёл' };
      }
      return ответ;
    }).catch(function () {
      return { принято: false, причина: 'Ход не удалось отправить' };
    });
  }

  /* -------------------------------------------------------------------
     Знаки внимания (смайлики, фразы, броски) — как в дураке и нардах.

     Саму панель ставит общий модуль общее/js/онлайн-лобби.js по просьбе
     игры/шахматы/шахматы-лобби.js (окно #экран-эмоций и полка #знаки-внимания —
     из общее/js/деберц-сказать.js). Здесь — две вещи: кнопка «Сказать»
     открывает панель, а каждый новый вид стола уходит в панель, чтобы
     знаки соперника появлялись на полке.

     Кнопки в разметке нет — мост ставит её сам перед «Сдаться», теми же
     классами. Видна она только в сетевой партии и только если сервер
     сказал, что знаки умеет (знакиВниманияЕсть).
     ------------------------------------------------------------------- */

  var ИМЯ_ИГРЫ = 'шахматы';

  /** Панель знаков от общего модуля. Нет модуля или панели — null. */
  function панельЗнаков() {
    var лобби = window.ОнлайнЛобби;
    if (!лобби || typeof лобби.панельЗнаков !== 'function') return null;
    return лобби.панельЗнаков(ИМЯ_ИГРЫ) || null;
  }

  function кнопкаЗнаков() {
    return document.getElementById('кнопка-эмоции');
  }

  /** Передать вид в панель: там она находит свежий знак и показывает его. */
  function передатьЗнаки(вид) {
    освежитьКнопкуЗнаков(вид);
    var панель = панельЗнаков();
    if (панель && typeof панель.принять === 'function') панель.принять(вид);
  }

  /**
   * Показать «Сказать» только когда сказать правда можно: идёт сетевая
   * партия, сервер знаки умеет и панель на странице стоит. Иначе кнопки
   * нет вовсе — мёртвых кнопок в сборнике не бывает.
   */
  function освежитьКнопкуЗнаков(вид) {
    var кнопка = кнопкаЗнаков();
    if (!кнопка) return;
    var можно = вПартии && Boolean(вид && вид.знакиВниманияЕсть) && Boolean(панельЗнаков());
    кнопка.classList.toggle('скрыт', !можно);
    кнопка.disabled = !можно;
  }

  function нажалиСказать() {
    var панель = панельЗнаков();
    if (вПартии && панель && typeof панель.открыть === 'function') панель.открыть();
  }

  /** Поставить кнопку «Сказать» перед «Сдаться» — один раз на страницу. */
  function подключитьКнопкуЗнаков() {
    if (кнопкаЗнаков()) return;
    var сдача = document.getElementById('кнопка-сдаться');
    if (!сдача || !сдача.parentNode) {
      console.error('Шахматы по сети: нет кнопки «Сдаться» — поставить «Сказать» некуда');
      return;
    }
    var кнопка = document.createElement('button');
    кнопка.id = 'кнопка-эмоции';
    кнопка.type = 'button';
    кнопка.className = 'кнопка кнопка--мелкая скрыт';
    кнопка.disabled = true;
    кнопка.textContent = 'Сказать';
    кнопка.addEventListener('click', нажалиСказать);
    сдача.parentNode.insertBefore(кнопка, сдача);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', подключитьКнопкуЗнаков);
  } else {
    подключитьКнопкуЗнаков();
  }

  window.ИграПоСети = {
    начать: начать,
    показатьВид: показатьВид,
    показатьСвязь: показатьСвязь,
    экран: экран,
    вМеню: вМеню,
    назадСоВхода: назадСоВхода,
    идёт: function () { return вПартии; }
  };

  /* Наружу — только для доски: ей надо знать, идёт ли сетевая партия,
     когда человек уходит со страницы или начинает партию с ботом. */
  window.ШахматыСеть = {
    идёт: function () { return вПартии; },
    покинуть: function () {
      var сеть = связь();
      отпуститьДоску();
      if (сеть && typeof сеть.покинутьПартию === 'function') сеть.покинутьПартию();
    }
  };
})();
