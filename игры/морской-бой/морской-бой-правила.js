'use strict';
/* Подтверждённый вариант: 10×10, флот 4/3/3/2/2/2/1/1/1/1,
 * без касаний, попадание сохраняет ход. См. штаб/план-морской-бой.md.
 * Общий модуль браузера и сервера; интерфейс не рассчитывает попадания. */
(function () {
  const СОСТАВ = Object.freeze([4, 3, 3, 2, 2, 2, 1, 1, 1, 1]);
  const клетка = n => Number.isInteger(n) && n >= 0 && n < 100;
  const рядом = (a, b) => Math.abs(a % 10 - b % 10) <= 1 && Math.abs(Math.floor(a / 10) - Math.floor(b / 10)) <= 1;
  function проверитьФлот(флот, полный = true) {
    if (!Array.isArray(флот) || флот.length > 10 || (полный && флот.length !== 10)) return 'Нужны десять кораблей';
    const занято = [], количества = [0, 0, 0, 0, 0], пределы = [0, 4, 3, 2, 1];
    for (const корабль of флот) {
      if (!Array.isArray(корабль) || корабль.length < 1 || корабль.length > 4) return 'Неверная длина корабля';
      if (++количества[корабль.length] > пределы[корабль.length]) return 'Неверный состав флота';
      if (Array.from(корабль).some(n => !клетка(n)) || new Set(корабль).size !== корабль.length) return 'Корабль выходит за поле или повторяет клетку';
      const к = [...корабль].sort((a, b) => a - b);
      const горизонталь = к.every((n, i) => Math.floor(n / 10) === Math.floor(к[0] / 10) && n === к[0] + i);
      const вертикаль = к.every((n, i) => n === к[0] + i * 10);
      if (!горизонталь && !вертикаль) return 'Корабль должен идти непрерывно по прямой';
      if (к.some(n => занято.some(m => рядом(n, m)))) return 'Корабли не должны касаться даже углами';
      занято.push(...к);
    }
    return null;
  }
  function случайныйФлот(случайно = Math.random) {
    const флот = []; let узлов = 0;
    function поставить(i) {
      if (i === СОСТАВ.length) return true;
      if (++узлов > 200000) throw Error('Не удалось подобрать флот');
      const длина = СОСТАВ[i], варианты = [];
      for (let n = 0; n < 100; n++) for (const шаг of длина === 1 ? [1] : [1, 10]) {
        if (шаг === 1 ? n % 10 + длина > 10 : Math.floor(n / 10) + длина > 10) continue;
        const к = Array.from({ length: длина }, (_, j) => n + j * шаг);
        if (!к.some(a => флот.some(с => с.some(b => рядом(a, b))))) варианты.push(к);
      }
      for (let j = варианты.length - 1; j > 0; j--) {
        const r = случайно(); if (!Number.isFinite(r) || r < 0 || r >= 1) throw Error('Неверный генератор случайности');
        const k = Math.floor(r * (j + 1)); [варианты[j], варианты[k]] = [варианты[k], варианты[j]];
      }
      for (const к of варианты) { флот.push(к); if (поставить(i + 1)) return true; флот.pop(); }
      return false;
    }
    if (!поставить(0)) throw Error('Не удалось подобрать флот');
    return флот;
  }
  function создать(первый = Math.random() < .5 ? 0 : 1) {
    if (первый !== 0 && первый !== 1) throw Error('Неверный первый игрок');
    return { версия: 1, фаза: 'расстановка', первый, ход: null, флоты: [null, null], готовы: [false, false],
      атаки: [Array(100).fill('неизвестно'), Array(100).fill('неизвестно')], выстрелы: [0, 0], попадания: [0, 0], потоплено: [0, 0], последний: null, победитель: null };
  }
  function игрок(i) { if (i !== 0 && i !== 1) throw Error('Неверный игрок'); }
  function готов(и, кто, флот) {
    игрок(кто);
    if (и.фаза !== 'расстановка' || и.готовы[кто]) throw Error('Расстановка уже подтверждена');
    const ошибка = проверитьФлот(флот); if (ошибка) throw Error(ошибка);
    и.флоты[кто] = флот.map(к => [...к]); и.готовы[кто] = true;
    if (и.готовы.every(Boolean)) { и.фаза = 'бой'; и.ход = и.первый; }
  }
  function стрелять(и, кто, куда) {
    игрок(кто);
    if (и.фаза !== 'бой' || и.ход !== кто) throw Error('Сейчас нельзя стрелять');
    if (!клетка(куда)) throw Error('Выберите клетку поля');
    const отметки = и.атаки[кто];
    if (отметки[куда] !== 'неизвестно') throw Error('Эта клетка уже проверена');
    const корабль = и.флоты[1 - кто].find(к => к.includes(куда));
    и.выстрелы[кто]++;
    let результат = 'мимо';
    if (!корабль) { отметки[куда] = 'мимо'; и.ход = 1 - кто; }
    else {
      и.попадания[кто]++; отметки[куда] = 'попадание'; результат = 'попадание';
      if (корабль.every(n => отметки[n] === 'попадание')) {
        результат = 'потоплен'; и.потоплено[кто]++;
        корабль.forEach(n => { отметки[n] = 'потоплен'; });
        for (let n = 0; n < 100; n++) if (отметки[n] === 'неизвестно' && корабль.some(m => рядом(n, m))) отметки[n] = 'пусто';
        if (и.потоплено[кто] === 10) { и.фаза = 'конец'; и.победитель = кто; и.ход = null; }
      }
    }
    и.последний = { игрок: кто, клетка: куда, результат };
    return { ...и.последний };
  }
  function сдаться(и, кто) {
    игрок(кто); if (и.фаза === 'конец') throw Error('Партия завершена');
    и.фаза = 'конец'; и.победитель = 1 - кто; и.ход = null; и.сдача = true;
  }
  function вид(и, кто) {
    игрок(кто);
    return { версия: и.версия, фаза: и.фаза, вашХод: и.фаза === 'бой' && и.ход === кто,
      готовы: [и.готовы[кто], и.готовы[1 - кто]], своиКорабли: (и.флоты[кто] || []).map(к => [...к]),
      вашиВыстрелы: [...и.атаки[кто]], поВам: [...и.атаки[1 - кто]],
      потопленоВами: и.потоплено[кто], потеряноВами: и.потоплено[1 - кто],
      статистика: [кто, 1 - кто].map(i => ({ выстрелы: и.выстрелы[i], попадания: и.попадания[i], точность: и.выстрелы[i] ? Math.round(и.попадания[i] * 100 / и.выстрелы[i]) : 0 })),
      последний: и.последний ? { ваш: и.последний.игрок === кто, клетка: и.последний.клетка, результат: и.последний.результат } : null,
      победа: и.фаза === 'конец' ? и.победитель === кто : null,
      флотСоперника: и.фаза === 'конец' ? (и.флоты[1 - кто] || []).map(к => [...к]) : null };
  }
  const правила = { СОСТАВ, проверитьФлот, случайныйФлот, создать, готов, стрелять, сдаться, вид };
  if (typeof module !== 'undefined' && module.exports) module.exports = правила;
  if (typeof window !== 'undefined') window.МорскойБойПравила = правила;
})();
