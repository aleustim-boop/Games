'use strict';
(function () {
  const П = typeof module !== 'undefined' && module.exports ? require('./деберц-правила.js') : window.ДеберцПравила;
  // Бот читает только свою руку и открытую карту взятки.
  function козырь(рука, варианты, уровень = 'обычный', случайно = Math.random) {
    if (уровень === 'лёгкий') return случайно() < .5 ? null : варианты[Math.floor(случайно() * варианты.length)];
    const оценка = масть => рука.reduce((с, к) => с + (к.масть === масть ? П.очки(к, масть) + 7 : П.очки(к, масть) / 3), 0)
      + (уровень === 'сложный' ? П.комбинации(рука, масть).reduce((с, к) => с + к.очки / 2, 0) : 0);
    const масть = варианты.slice().sort((a, b) => оценка(b) - оценка(a))[0];
    return оценка(масть) >= 38 ? масть : null;
  }
  function карта(доступные, первая, козырь, уровень = 'обычный', сыграно = [], случайно = Math.random, напарникБерёт = false) {
    if (уровень === 'лёгкий') return доступные[Math.floor(случайно() * доступные.length)];
    const цена = к => П.очки(к, козырь) + П.сила(к, козырь) / 10 + (к.масть === козырь ? 4 : 0);
    // Когда взятка у напарника, не перебиваем его без необходимости.
    if (напарникБерёт) {
      const неБьют = доступные.filter(к => !П.бьёт(к, первая, козырь));
      if (неБьют.length) return неБьют.slice().sort((a, b) => П.очки(b, козырь) - П.очки(a, козырь))[0];
    }
    const выигрышные = первая ? доступные.filter(к => П.бьёт(к, первая, козырь)) : [];
    if (уровень === 'сложный' && !первая) {
      // Старший бот помнит только открыто сыгранные карты. Рука человека
      // и остаток колоды сюда не передаются. Мастер-карта: старших в игре
      // уже не осталось; среди них прежде забираем дорогие некозырные.
      const известны = new Set([...сыграно, ...доступные].map(к => к.id));
      const старшие = доступные.filter(к => П.ряд.every(имя => {
        const кандидат = { имя, масть: к.масть };
        return !П.бьёт(кандидат, к, козырь) || известны.has(к.масть + имя);
      }));
      if (старшие.length) return старшие.sort((a, b) =>
        (П.очки(b, козырь) - (b.масть === козырь ? 15 : 0)) -
        (П.очки(a, козырь) - (a.масть === козырь ? 15 : 0)))[0];
    }
    return (выигрышные.length ? выигрышные : доступные).slice().sort((a, b) => цена(a) - цена(b))[0];
  }
  const бот = { козырь, карта };
  if (typeof module !== 'undefined' && module.exports) module.exports = бот;
  if (typeof window !== 'undefined') window.ДеберцБот = бот;
})();
