    // Стол открыл свой лист: экран и онлайн закрывают свои (вопрос об остатке, «Поставить сюда», журнал).
    // Что открыто — 'приказ' или 'карточка'.
    function сказатьОбОткрытииЛиста(что) {
      if (слушатели.приОткрытииЛиста) слушатели.приОткрытииЛиста(что);
    }

