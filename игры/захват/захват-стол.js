  // Где карта лежит в узле карты (ТЗ 8.4, графика 4.3 п. 9): холст и море — на весь узел, карта с полем —
  // по центру. По ширине карта во всю ширину узла; если тогда она выше узла — уменьшается до его высоты.
  // Холст (экран, сеть) и слой шайб (стол) берут место отсюда, поэтому их координаты не разъезжаются.
  // Размеры карты считает только ЗахватКартаВид.геометрия: её высота растёт ровно пропорционально ширине.
  // высотаУзла 0 или неизвестна (проверки на node) — карта от верхнего края, холст высотой с карту.
  // Отдаёт { ширина, высота } карты с полем и { x, y } — её левый верхний угол в узле, в CSS px.
  // занятыйНиз — сколько px снизу окна занято пилюлей подсказки (её мерит экран). Карта сдвигается ровно
  // на нужное, а не центруется над пилюлей (ТЗ 13): пусть «без отступа» — место карты при занятыйНиз = 0,
  // граница = высота окна − занятыйНиз. Низ карты не выше границы — карта на месте «без отступа»; не
  // помещается, но карта ниже границы по высоте — тот же масштаб, низ карты встаёт на границу; выше
  // границы — вписана в границу, y = 0. Не задан или 0 — как раньше. Без высоты окна (node) отступ не нужен.
  //
  // окно { верх, низ } (П6, ТЗ 8.4 «Окно карты») — полоса узла между капсулами игроков и пультом в
