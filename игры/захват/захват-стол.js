  function местоКарты(партия, ширинаУзла, высотаУзла, занятыйНиз, окно) {
    if (окно && окно.низ > окно.верх) return местоВОкне(партия, ширинаУзла, высотаУзла, занятыйНиз, окно);
    const карта = Правила.картаПартии(партия);
    const полная = КартаВид.геометрия(карта, ширинаУзла);
    let г = полная;
    if (высотаУзла > 0 && г.высота > высотаУзла) г = КартаВид.геометрия(карта, ширинаУзла * высотаУзла / г.высота);
    const место = {
      ширина: г.ширина,
      высота: г.высота,
      x: (ширинаУзла - г.ширина) / 2,
      y: высотаУзла > 0 ? (высотаУзла - г.высота) / 2 : 0
    };
    if (!(высотаУзла > 0) || !(занятыйНиз > 0)) return место;
    const граница = Math.max(1, высотаУзла - занятыйНиз);
    if (место.y + место.высота <= граница) return место;
    if (место.высота <= граница) {
      место.y = граница - место.высота;
      return место;
    }
    г = КартаВид.геометрия(карта, ширинаУзла * граница / полная.высота);
    return { ширина: г.ширина, высота: г.высота, x: (ширинаУзла - г.ширина) / 2, y: 0 };
  }

  // Наибольшая ширина карты в px: не больше собственной ширины листа земли в точках, делённой на плотность
  // экрана, — картинку не растягиваем больше её размера. Ключ не дан (капсулы не сбоку) или у пробной
  // карты нет листа — предела нет (Infinity): обычная раскладка не меняется.
  function пределШириныКарты(ключКарты) {
    if (!ключКарты) return Infinity;
    const лист = КартаВид.РАЗМЕРЫ && КартаВид.РАЗМЕРЫ['земля-' + ключКарты];
    if (!лист || !(лист.ширина > 0)) return Infinity;
    const плотность = (typeof window !== 'undefined' && window.devicePixelRatio > 0) ? window.devicePixelRatio : 1;
    return лист.ширина / плотность;
  }

  // Карта во всю ширину полосы [лево, право] (не задано — весь узел), но не шире листа земли и не выше полосы
  // [верх, низ]: выше — уменьшается до неё. Стоит по центру полосы.
  function картаВПолосе(карта, ширинаУзла, верх, низ, лево, право, ключКарты) {
    const границаЛево = лево > 0 ? лево : 0;
    const границаПраво = право > границаЛево ? право : ширинаУзла;
    const ширинаПолосы = границаПраво - границаЛево;
    const высотаПолосы = Math.max(1, низ - верх);
    let г = КартаВид.геометрия(карта, Math.min(ширинаПолосы, пределШириныКарты(ключКарты)));
    if (г.высота > высотаПолосы) г = КартаВид.геометрия(карта, г.ширина * высотаПолосы / г.высота);
    return {
      ширина: г.ширина,
      высота: г.высота,
      x: границаЛево + (ширинаПолосы - г.ширина) / 2,
      y: верх + (высотаПолосы - г.высота) / 2
    };
  }

  function местоВОкне(партия, ширинаУзла, высотаУзла, занятыйНиз, окно) {
    const карта = Правила.картаПартии(партия);
    const ключПредела = окно.сбоку ? партия.карта : null;
    const место = картаВПолосе(карта, ширинаУзла, окно.верх, окно.низ, окно.лево, окно.право, ключПредела);
    if (!(высотаУзла > 0) || !(занятыйНиз > 0)) return место;
    const граница = Math.max(окно.верх + 1, Math.min(окно.низ, высотаУзла - занятыйНиз));
    if (место.y + место.высота <= граница) return место;
    if (место.высота <= граница - окно.верх) {
      место.y = граница - место.высота;
      return место;
    }
    const вписана = картаВПолосе(карта, ширинаУзла, окно.верх, граница, окно.лево, окно.право, ключПредела);
    вписана.y = окно.верх;
    return вписана;
  }

  // Зазор между окном карты и тем, что над и под ним (капсулы игроков, пульт), в CSS px (ТЗ 8.4).
  const ЗАЗОР_ОКНА_PX = 8;
  // Отступ окна карты от столбца капсул слева и от правого края экрана на широком окне, CSS px.
  const ПОЛЕ_ОКНА_PX = 12;
  // Во сколько раз место вне окна карты хуже такого же налегания на шайбу (выбор места подписи).
  const ШТРАФ_ЗА_ВЫХОД_ИЗ_ОКНА = 50;

  // Окно карты (П6, ТЗ 8.4 «Окно карты»): { верх, низ, лево, право } в px от левого верха узла #захват-карта.
  // верх = низ капсул игроков + 8; низ = низ содержимого #экран-игры (над полями и полосой Telegram) −
  // --захват-пульт-наибольший − 8. Берётся наибольший пульт, а не нынешний: окно не зависит от фазы, и
  // остров не прыгает, когда пульт растёт или уходит под лист. Замерить нечем (node, узлов нет) — null.
  function замеритьОкно(документ) {
    const д = документ || (typeof document !== 'undefined' ? document : null);
    if (!д) return null;
    const узелКарты = д.getElementById('захват-карта');
    const игроки = д.getElementById('захват-игроки');
    const экран = д.getElementById('экран-игры');
    const вид = д.defaultView;
    if (!узелКарты || !игроки || !экран || !вид || !вид.getComputedStyle) return null;
    if (!узелКарты.getBoundingClientRect || !игроки.getBoundingClientRect || !экран.getBoundingClientRect) return null;
    const верхКарты = узелКарты.getBoundingClientRect().top;
    const стиль = вид.getComputedStyle(экран);
    const наибольший = parseFloat(стиль.getPropertyValue ? стиль.getPropertyValue('--захват-пульт-наибольший') : '');
    const низСодержимого = экран.getBoundingClientRect().bottom - (parseFloat(стиль.borderBottomWidth) || 0) -
      parseFloat(стиль.paddingBottom);
    const рамкаУзла = узелКарты.getBoundingClientRect();
    const ширинаУзла = рамкаУзла.right - рамкаУзла.left;
    const окно = {
      верх: игроки.getBoundingClientRect().bottom - верхКарты + ЗАЗОР_ОКНА_PX,
      низ: низСодержимого - наибольший - ЗАЗОР_ОКНА_PX - верхКарты,
      лево: 0,
      право: ширинаУзла
    };
    if (капсулыСбоку(д, вид)) {
      const рамкаИгроков = игроки.getBoundingClientRect();
      // Столбец капсул скрыт (нулевая рамка) — слева держим только поле.
      const столбецВидим = рамкаИгроков.right - рамкаИгроков.left > 0 && рамкаИгроков.bottom - рамкаИгроков.top > 0;
      окно.сбоку = true;
      окно.лево = столбецВидим ? рамкаИгроков.right + ПОЛЕ_ОКНА_PX - рамкаУзла.left : ПОЛЕ_ОКНА_PX;
      окно.право = ширинаУзла - ПОЛЕ_ОКНА_PX;
      окно.верх = верхОкнаСбоку(д, экран, окно, рамкаУзла, стиль);
      if (!isFinite(окно.лево) || !isFinite(окно.право) || окно.право <= окно.лево) return null;
    }
    if (!isFinite(окно.верх) || !isFinite(окно.низ) || окно.низ <= окно.верх) return null;
    поднятьНизНадЛистом(д, окно, верхКарты);
    return окно;
  }

  // Не ниже этого окно карты над листом удара не сжимаем: меньше — карта станет с ноготь (задача 70), px.
  const МИН_ВЫСОТА_ОКНА_НАД_ЛИСТОМ_PX = 150;

  // Пока открыт лист удара (#захват-приказ), окно карты кончается над ним: цель и источник удара остаются
  // видны, а не прячутся под листом. Лист стоит поверх экрана (fixed), поэтому его верх берём по offsetTop,
  // а не по рамке: рамка прыгает, пока лист выезжает анимацией. Листа нет или он скрыт — окно как было.
  function поднятьНизНадЛистом(д, окно, верхКарты) {
    const лист = д.getElementById('захват-приказ');
    if (!лист || лист.classList.contains('скрыт') || !(лист.offsetHeight > 0)) return;
    const верхЛиста = лист.offsetTop - верхКарты - ЗАЗОР_ОКНА_PX;
    if (!isFinite(верхЛиста)) return;
    окно.низ = Math.min(окно.низ, Math.max(окно.верх + МИН_ВЫСОТА_ОКНА_НАД_ЛИСТОМ_PX, верхЛиста));
  }

  // Признак «капсулы игроков стоят сбоку» (широкое окно): число --захват-капсулы-сбоку на body, его задаёт
  // оформление. Нет переменной или 0 — раскладка телефона, окно карты как раньше.
  function капсулыСбоку(д, вид) {
    if (!д.body) return false;
    const стильТела = вид.getComputedStyle(д.body);
    const число = parseFloat(стильТела && стильТела.getPropertyValue ? стильТела.getPropertyValue('--захват-капсулы-сбоку') : '');
    return число > 0;
  }

  // Верх окна при капсулах сбоку: низ самого нижнего из «.верх-игры» и «#захват-игроки», что заходит
  // по горизонтали в полосу [лево, право], + 8; никто не заходит (Telegram, столбец слева) — верхнее поле экрана.
  function верхОкнаСбоку(д, экран, окно, рамкаУзла, стильЭкрана) {
    const левоПолосы = рамкаУзла.left + окно.лево;
    const правоПолосы = рамкаУзла.left + окно.право;
    // Строк «.верх-игры» на странице несколько (лобби, настройки, партия): берём все, невидимые отсеет проверка высоты.
    // Нет querySelectorAll (простой документ без него) — берём первую через querySelector.
    let строки = [];
    if (д.querySelectorAll) строки = Array.prototype.slice.call(д.querySelectorAll('.верх-игры'));
    else if (д.querySelector) строки = [д.querySelector('.верх-игры')];
    const над = [д.getElementById('захват-игроки')].concat(строки);
    let низНад = null;
    над.forEach(function (у) {
      if (!у || !у.getBoundingClientRect) return;
      const р = у.getBoundingClientRect();
      if (!(р.height > 0) || !(р.right > левоПолосы) || !(р.left < правоПолосы)) return;
      if (низНад === null || р.bottom > низНад) низНад = р.bottom;
    });
    if (низНад !== null) return низНад + ЗАЗОР_ОКНА_PX - рамкаУзла.top;
    const поле = (parseFloat(стильЭкрана.borderTopWidth) || 0) + (parseFloat(стильЭкрана.paddingTop) || 0);
    return экран.getBoundingClientRect().top + поле - рамкаУзла.top;
  }

