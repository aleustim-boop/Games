/*
 * Привратник команд.
 *
 * Зачем он: владельца дёргало окно «разрешить эту команду?» даже тогда, когда
 * команда была совершенно безобидной. Причина не в нехватке разрешений — их в
 * settings.local.json выдано с избытком. Причина в склейке: когда исполнитель
 * пишет в одну команду cd + mkdir + cp + node + rm, такая строка не подходит
 * целиком ни под одно правило, и спрашивается всегда, сколько правил ни выдай.
 *
 * Что делает: читает команду и сам разрешает её, если в ней нет ничего
 * по-настоящему опасного. Если опасное есть — молчит, и тогда всё идёт старым
 * путём: владельца спрашивают, как и раньше.
 *
 * Опасным считаем ровно то, что названо опасным в правилах владельца и проекта:
 * необратимое (снос файлов, откат git, принудительный пуш), секреты (bot/.env),
 * боевой сервер комнат на порту 8790 и широкое убийство процессов.
 *
 * Важно: этот привратник НИЧЕГО не запрещает. Он умеет только «разрешаю» и
 * «сам решай как обычно». Запрет остаётся за владельцем.
 */

'use strict';

/* ——— Что считаем опасным. Каждая строка — почему она здесь. ——— */
const ОПАСНОЕ = [
  // Необратимый снос. rm -f снимков и временных папок разрешён отдельно ниже.
  { примета: /\brm\s+(-[a-zA-Z]*r[a-zA-Z]*f|-[a-zA-Z]*f[a-zA-Z]*r)\b/, почему: 'сносит папку целиком' },
  { примета: /\bRemove-Item\b[^\n]*-Recurse/i, почему: 'сносит папку целиком' },
  { примета: /\brmdir\s+\/s/i, почему: 'сносит папку целиком' },

  // Откат git — уносит несохранённую работу исполнителей.
  { примета: /\bgit\s+reset\s+--hard\b/, почему: 'откат git уносит несохранённое' },
  { примета: /\bgit\s+clean\b/, почему: 'git clean уносит несохранённое' },
  { примета: /\bgit\s+checkout\s+--\s/, почему: 'откат файла уносит несохранённое' },
  { примета: /\bgit\s+restore\b/, почему: 'откат файла уносит несохранённое' },
  { примета: /--force\b|--hard\b|-f\s+origin\b/, почему: 'принудительное действие' },

  // Секреты. Токен бота живёт в bot/.env, входа туда нет никому.
  { примета: /bot[\/\\]\.env/i, почему: 'секреты бота' },
  { примета: /\.env\b/, почему: 'секреты' },

  // Боевой сервер комнат: на нём играют прямо сейчас.
  { примета: /\b8790\b/, почему: 'боевой сервер комнат' },

  // Широкое убийство процессов — правилами проекта запрещено, гасить по PID.
  { примета: /\btaskkill\b(?![^\n]*\/PID)/i, почему: 'широкое убийство процессов' },
  { примета: /\bStop-Process\b(?![^\n]*-Id\b)/i, почему: 'широкое убийство процессов' },
  { примета: /\bkillall\b/, почему: 'широкое убийство процессов' },
  { примета: /\bpkill\b/, почему: 'широкое убийство процессов' },

  // Чужие руки: установка пакетов и выход в сеть за пределы своих адресов.
  { примета: /\bnpm\s+(i|install|publish)\b/, почему: 'ставит пакеты' },
  { примета: /\bcurl\b[^\n]*-X\s*(POST|PUT|DELETE)/i, почему: 'пишет наружу' },

  // Правилами проекта запрещено прямо.
  { примета: /\btar\b/, почему: 'запрещено правилами проекта' },
  { примета: /\bpython\b/, почему: 'запрещено правилами проекта, только node' },
];

/* Снос временного — не опасен: это уборка за собой, и только в своей песочнице. */
const УБОРКА_ЗА_СОБОЙ = [
  /\brm\s+-rf?\s+["']?\$?\{?(TEMP|TMP|TMPDIR)\}?[\/\\]/i,
  /\brm\s+-rf?\s+["']?[^"'\s]*[\/\\](Temp|tmp)[\/\\]/i,
  /\brm\s+-f\s+[^\n]*\.png\b/,
];

function разобратьВход(сырое) {
  try {
    return JSON.parse(сырое);
  } catch (e) {
    return null;
  }
}

function командаИзВхода(вход) {
  const дано = (вход && вход.tool_input) || {};
  return String(дано.command || дано.script || '');
}

function проверить(команда) {
  if (!команда.trim()) return { разрешить: false, почему: 'пустая команда' };

  const уборка = УБОРКА_ЗА_СОБОЙ.some((п) => п.test(команда));

  for (const случай of ОПАСНОЕ) {
    if (!случай.примета.test(команда)) continue;
    // Снос своей временной папки — не повод будить владельца.
    if (уборка && /rm|Remove-Item|rmdir/i.test(случай.примета.source)) continue;
    return { разрешить: false, почему: случай.почему };
  }

  return { разрешить: true, почему: 'опасного не нашлось' };
}

function ответить(итог) {
  if (!итог.разрешить) {
    // Молчим: пусть решает владелец, как и раньше.
    process.exit(0);
  }
  const ответ = {
    hookSpecificOutput: {
      hookEventName: 'PreToolUse',
      permissionDecision: 'allow',
      permissionDecisionReason: 'Привратник команд: ' + итог.почему,
    },
  };
  process.stdout.write(JSON.stringify(ответ));
  process.exit(0);
}

let буфер = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (кусок) => {
  буфер += кусок;
});
process.stdin.on('end', () => {
  const вход = разобратьВход(буфер);
  if (!вход) process.exit(0);
  ответить(проверить(командаИзВхода(вход)));
});

/* Даёт себя проверить: node разрешение-команд.js --проверить */
if (process.argv.includes('--проверить')) {
  const случаи = [
    ['cd "D:\\Claud\\Games"\nmkdir -p "$TEMP/проверка"\ncp a b\nnode x.js\nrm -rf "$TEMP/проверка"', true],
    ['node tests/аватар-везде.js', true],
    ['git status', true],
    ['rm -rf D:/Claud/Games/js', false],
    ['cat bot/.env', false],
    ['curl -s http://127.0.0.1:8790/комнаты', false],
    ['taskkill /F /IM node.exe', false],
    ['taskkill /F /PID 1234', true],
    ['git reset --hard origin/main', false],
    ['node server/сервер.js --порт 8123', true],
  ];
  let провалов = 0;
  for (const [команда, ждём] of случаи) {
    const итог = проверить(команда).разрешить;
    if (итог !== ждём) {
      провалов++;
      console.log('ПРОВАЛ: ' + JSON.stringify(команда) + ' → ' + итог + ', ждали ' + ждём);
    }
  }
  console.log(провалов ? 'провалов: ' + провалов : 'все ' + случаи.length + ' случаев верны');
  process.exit(провалов ? 1 : 0);
}
