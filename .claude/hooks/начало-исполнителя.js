// PostToolUse-хук (matcher "Agent"): исполнитель запущен — отмечает «начал»
// в штаб/в-работе.json и заводит запись в штаб/права.json (роль → файлы
// из строки «Файлы:» задания, время начала). Права.json — источник правды
// для .claude/hooks/охрана-файлов.js.
//
// Ключ записи в правах и в-работе — номер исполнителя (agentId, тот же
// 16-значный, что достаёт извлечьНомерАгента()), а не роль: 22.09 штаб
// запустил двух developer параллельно, и запись по роли одного стёрла
// запись другого — охрана осталась вслепую. Номер не нашёлся — старый
// запасной путь: ключ роль, как раньше (и поля «номер» в записи нет).
//
// Строку «Файлы: …» штаб пишет обычным предложением, а не списком путей
// («Файлы: js/game.js и server/игры/шашки.js — только они. Понадобился
// другой — остановись…»): наивный split по запятой ловил в права.json
// обрывки фраз вроде «только они» и охрана блокировала исполнителя на его
// же файле (было 22.09). Разбор вынесен в путиИзСтроки() ниже — она режет
// строку на слова и оставляет только похожие на путь или маску.
//
// Номер записи исполнителя (поле «задача» у работы — его ждут штаб/живость.js
// и штаб/кто-молчит.js, чтобы найти файл записей и понять, жив ли исполнитель)
// добывается из ответа самого вызова Agent. Документация code.claude.com это
// поле не описывает, но на деле tool_response содержит строку вида
// «agentId: a6195cc40a6b690dd» — ровно то же имя (буква a и 15 шестнадцатеричных
// знаков), каким на диске называется файл записей agent-<номер>.jsonl/.meta.json
// (проверено: у текущего исполнителя agentId из примера штаба совпал с его же
// настоящим файлом записей). Извлекает извлечьНомерАгента() ниже — она читает
// tool_response как строку, как объект с полями content/text/agentId, как
// массив кусков, и как JSON.stringify на крайний случай. Не нашли номер — поле
// «задача» просто не пишется, как и раньше: тогда живость.js по-прежнему
// связывает работу с записью по роли (запасной путь, который она умеет
// с самого начала).
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..', '..');
const ФАЙЛ_ПРАВ = path.join(КОРЕНЬ, 'штаб', 'права.json');
const ФАЙЛ_РАБОТ = path.join(КОРЕНЬ, 'штаб', 'в-работе.json');

function читатьВход() {
  let текст = '';
  try { текст = fs.readFileSync(0, 'utf8'); } catch (о) { return null; }
  try { return JSON.parse(текст); } catch (о) { return null; }
}
function читатьJSON(файл, поУмолчанию) {
  try { return JSON.parse(fs.readFileSync(файл, 'utf8')); } catch (о) { return поУмолчанию; }
}
function времяЗаписью(дата) {
  const дв = (ч) => String(ч).padStart(2, '0');
  return дата.getFullYear() + '-' + дв(дата.getMonth() + 1) + '-' + дв(дата.getDate())
    + ' ' + дв(дата.getHours()) + ':' + дв(дата.getMinutes());
}

/**
 * Номер записи исполнителя (agentId) из ответа инструмента Agent.
 *
 * tool_response приходит по-разному: то простой строкой с текстом вида
 * «Async agent launched successfully... agentId: a6195cc40a6b690dd ...»,
 * то объектом или массивом кусков с полями content/text, то, возможно,
 * с полем agentId/agent_id напрямую. Поэтому собираем все строки, где номер
 * теоретически может быть, и как крайний случай — весь ответ, обращённый
 * в JSON: если форма ответа когда-нибудь изменится, регулярка всё равно
 * может зацепиться за сериализованный текст.
 *
 * Не нашли — честный null, побочных действий эта функция не делает.
 */
function извлечьНомерАгента(ответ) {
  if (ответ === null || ответ === undefined) return null;

  const РЕГУЛЯРКА = /agent[_-]?id["']?\s*[:=]\s*["']?([a-z0-9]{8,})/i;
  const тексты = [];

  function собрать(значение) {
    if (typeof значение === 'string') { тексты.push(значение); return; }
    if (Array.isArray(значение)) { значение.forEach(собрать); return; }
    if (значение && typeof значение === 'object') {
      if (typeof значение.content === 'string') тексты.push(значение.content);
      if (typeof значение.text === 'string') тексты.push(значение.text);
      if (typeof значение.agentId === 'string') тексты.push(значение.agentId);
      if (typeof значение.agent_id === 'string') тексты.push(значение.agent_id);
      if (Array.isArray(значение.content)) значение.content.forEach(собрать);
    }
  }
  собрать(ответ);
  try { тексты.push(JSON.stringify(ответ)); } catch (о) { /* не сериализуется — не беда, другие куски уже собраны */ }

  for (const текст of тексты) {
    const совпадение = РЕГУЛЯРКА.exec(текст);
    if (совпадение) return совпадение[1].toLowerCase();
  }
  return null;
}

/**
 * Достаёт пути и маски файлов из строки «Файлы: …», написанной обычным
 * предложением. Разбивает по запятым, точкам с запятой, пробелам и союзу
 * «и» как отдельному слову; у каждого куска срезает по краям кавычки
 * (обычные «» "" `` и типографские “” ‘’), скобки, тире и двоеточие (но
 * НЕ точку слева — иначе слетит ведущая точка скрытых путей вроде
 * «.claude/hooks/…»). Звёздочки по краям куска (жирный текст разметки
 * вроде «**горит**») срезаются отдельным шагом, тоже как кавычки — но
 * важно, была ли звёздочка вообще ДО среза: кусок «tests/*» после среза
 * превращается в «tests/» и получает звёздочку назад ниже (как обычная
 * папка), а кусок, где звёздочка была и после среза не осталось «/»
 * (например «*.png» без папки), не принимается вовсе — иначе он выглядел
 * бы как голое «.png» с «расширением» и проходил бы как файл (ревью 24.09,
 * пункт 2: маска-подстрока без границы папки).
 *
 * Кусок считается путём/маской, только если:
 *   — оканчивается на «/» (целая папка — станет маской «папка/*»), либо
 *   — до среза звёздочек в куске была «*» — тогда принимается, только
 *     если после среза в нём остался «/» (голая «*» или «*.png» без
 *     папки — не путь, слишком широкая маска), либо
 *   — похоже на имя файла: точка и 1–10 латинских букв/цифр, где ХОТЯ БЫ
 *     ОДНА буква обязательна (иначе «24.09» ловилась бы как файл с
 *     «расширением» «09»), либо последний кусок пути (без учёта регистра)
 *     совпадает с известным именем файла без расширения: .gitignore,
 *     Procfile, Dockerfile, Makefile.
 *
 * И даже тогда — предохранитель: после удаления «.», «/» и «*» в куске
 * обязана остаться хотя бы одна буква или цифра (латиница или кириллица).
 * Без него голые разделители «./», «../», «/» превращались бы в «папку» и
 * давали маску «*» = весь проект (ревью 24.09, пункт 1 — самое тяжёлое:
 * охрана-файлов.js после нормализации сравнивает такую маску как «пусто
 * между звёздочками» и пропускает ЛЮБОЙ путь).
 *
 * Второй круг ревью 24.09: одного предохранителя мало — «tests/../» (и
 * жирное «**tests/../**») буквы в куске ЕСТЬ («tests»), предохранитель
 * пропускал, а после сборки маски «tests/../*» охрана-файлов.js схлопывает
 * «tests/..» при нормализации и снова получает маску на весь проект. Штаб
 * так пути не пишет вообще — «..» отбрасывается сразу, как только это
 * отдельный сегмент пути (кусок между «/», split('/').includes('..')), ещё
 * до сборки маски. Отдельно, уже ПОСЛЕ сборки маски — вторая, независимая
 * сеть: маска прогоняется через path.posix.normalize() и отбрасывается,
 * если результат начинается с «..», равен «*», «.» или «./*», либо после
 * удаления из него всех «*» не осталось ни одной буквы/цифры. Первая
 * проверка ловит по смыслу («..» — это «выйти из папки»), вторая — по
 * итоговому виду маски, на случай если что-то проскочило мимо первой.
 *
 * Третий круг ревью 24.09: «tests\../» (обратный слэш) обходил ОБА
 * заслона — split('/') не считает «\» разделителем сегментов, а
 * path.posix.normalize() тоже не понимает «\» как путь-разделитель, поэтому
 * маска «tests\../*» проходила посикс-проверку невредимой; на Windows же
 * охрана-файлов.js сравнивает пути через системный path.join/path.relative
 * (win32-семантика), который «\» разделителем как раз считает и схлопывает
 * её в маску на весь проект. Штаб пишет пути только через «/» — самый
 * простой и надёжный способ: токен с «\» отбрасывается целиком, ещё до
 * всех остальных проверок. Дополнительно вторая сеть (маскаБезопасна)
 * теперь проверяет ОБЕ нормализации — path.posix и path.win32 — одной и
 * той же логикой (она не завязана на конкретный разделитель), на случай
 * если что-то в обход первого фильтра всё же дойдёт до сборки маски.
 *
 * Порядок сохраняется, точные повторы убираются; файл без папки, чей
 * хвост совпал с уже найденным путём (кто-молчит.js после штаб/кто-молчит.js),
 * тоже считается повтором и отбрасывается.
 *
 * Пусто на непустой строке — не тихая беда: предупреждение в stderr,
 * дальше пустой список файлов (как и раньше при отсутствии строки «Файлы:»).
 *
 * Важно (правка 23.09): пустой список файлы:[] — не «можно всё». Запись
 * всё равно заводится с файлы:[] (как и раньше), но теперь охрана-файлов.js
 * трактует пустой список у НАЙДЕННОЙ записи исполнителя как запрет править
 * файлы проекта (кроме временных путей) и просит спросить штаб. Здесь
 * менять нечего — источник дыры был в охране, не в разборе строки.
 */
function путиИзСтроки(строка) {
  if (!строка) return [];
  строка = String(строка);

  const КРАЙ_СЛЕВА = /^[«»"'`“”‘’(),:;\-—–]+/;
  const КРАЙ_СПРАВА = /[«»"'`“”‘’(),.:;\-—–]+$/;
  // Известные имена файлов без «.расширения» — сверяем последний кусок
  // пути без учёта регистра (bot/Procfile тоже подходит).
  const ИМЕНА_БЕЗ_РАСШИРЕНИЯ = ['procfile', 'dockerfile', 'makefile'];

  function выглядитКакФайл(кусок) {
    const совпадение = /\.([a-zA-Z0-9]{1,10})$/.exec(кусок);
    if (совпадение && /[a-zA-Z]/.test(совпадение[1])) return true; // хотя бы одна буква — не голые цифры вроде «24.09»
    const последний = кусок.split('/').pop().toLowerCase();
    return ИМЕНА_БЕЗ_РАСШИРЕНИЯ.includes(последний);
  }

  // Вторая, независимая сеть (после сборки маски): нормализуем и смотрим,
  // не схлопнулось ли всё в «выйти из проекта» или «пусто = весь проект».
  // Третий круг ревью 24.09: одной posix-нормализации мало — на Windows
  // охрана-файлов.js сравнивает пути через системный path (win32), а он
  // считает «\» разделителем и схлопывает «..» иначе, чем posix. Проверяем
  // ОБЕ нормализации одной и той же логикой — она не завязана на конкретный
  // разделитель (startsWith('..') и «нет буквы/цифры после звёздочек»
  // работают что для «../», что для «..\»).
  function маскаОпасна(нормализованная) {
    if (нормализованная.startsWith('..')) return true;
    if (нормализованная === '*' || нормализованная === '.' || нормализованная === './*') return true;
    const безЗвёздочек = нормализованная.replace(/\*/g, '');
    if (!/[A-Za-zА-Яа-яЁё0-9]/.test(безЗвёздочек)) return true;
    return false;
  }

  function маскаБезопасна(маска) {
    if (маскаОпасна(path.posix.normalize(маска))) return false;
    if (маскаОпасна(path.win32.normalize(маска))) return false;
    return true;
  }

  const найденные = [];
  const токены = строка.split(/[,;\s]+/).filter(Boolean);
  for (const сырое of токены) {
    if (/^и$/i.test(сырое)) continue; // союз «и» — не путь

    const послеОбычнойОбрезки = сырое.replace(КРАЙ_СЛЕВА, '').replace(КРАЙ_СПРАВА, '');
    if (!послеОбычнойОбрезки) continue;

    // Штаб пишет пути только через «/» — «\» целиком не путь, отбрасываем
    // сразу весь токен (третий круг ревью 24.09: «tests\../» не разбивается
    // split('/') на сегменты и обходит запрет «..» отдельным сегментом).
    if (послеОбычнойОбрезки.includes('\\')) continue;

    const звёздочкаБылаИсходно = послеОбычнойОбрезки.includes('*'); // проверяем ДО среза звёздочек по краям
    const токен = послеОбычнойОбрезки.replace(/^\*+/, '').replace(/\*+$/, '');
    if (!токен) continue;

    const этоПапка = токен.endsWith('/');
    const похожНаПуть = этоПапка
      ? true
      : звёздочкаБылаИсходно
        ? токен.includes('/') // маска принимается только вместе со слешем — голая «*»/«*.png» без папки отбрасывается
        : выглядитКакФайл(токен);
    if (!похожНаПуть) continue;

    // «..» отдельным сегментом пути — штаб так пути не пишет никогда,
    // отбрасываем сразу: «tests/../» иначе даёт маску на весь проект после
    // схлопывания «tests/..» при нормализации в охране (ревью 24.09, круг 2).
    if (токен.split('/').includes('..')) continue;

    // Предохранитель: без буквы/цифры это голый разделитель («./», «../»,
    // «/»), не путь — иначе он превратился бы в маску «*» на весь проект.
    const очищенный = токен.replace(/[./*]/g, '');
    if (!/[A-Za-zА-Яа-яЁё0-9]/.test(очищенный)) continue;

    const маска = этоПапка ? токен + '*' : токен;
    if (!маскаБезопасна(маска)) continue;

    найденные.push(маска);
  }

  const итог = [];
  for (const токен of найденные) {
    if (итог.includes(токен)) continue;
    if (!токен.includes('/') && итог.some((п) => п.endsWith('/' + токен))) continue;
    итог.push(токен);
  }

  if (итог.length === 0 && строка.trim()) {
    console.error('начало-исполнителя: в строке «Файлы:» не нашлось ни одного пути: ' + строка.trim());
  }
  return итог;
}

/** Весь побочный ход хука: чтение входа, запись прав и работы, пересборка ЗАДАЧИ.md. */
function основнойХод() {
  const данные = читатьВход();
  if (!данные || данные.tool_name !== 'Agent') return;

  const вход = данные.tool_input || {};
  const роль = String(вход.subagent_type || '').trim();
  if (!роль) return;

  const описание = String(вход.description || роль);
  const задание = String(вход.prompt || '');
  const строкаФайлов = /Файлы:\s*(.+)/.exec(задание);
  const файлы = строкаФайлов ? путиИзСтроки(строкаФайлов[1]) : [];

  const сейчас = времяЗаписью(new Date());
  const номерАгента = извлечьНомерАгента(данные.tool_response);

  const ключПрав = номерАгента || роль;
  const права = читатьJSON(ФАЙЛ_ПРАВ, {});
  const записьПрав = { имя: роль, роль: роль, файлы: файлы, начал: сейчас };
  if (номерАгента) записьПрав.номер = номерАгента;
  права[ключПрав] = записьПрав;
  try { fs.writeFileSync(ФАЙЛ_ПРАВ, JSON.stringify(права, null, 2) + '\n', 'utf8'); } catch (о) { console.error('охрана: не удалось записать права.json: ' + о.message); }

  const работы = читатьJSON(ФАЙЛ_РАБОТ, { работы: [] });
  if (!Array.isArray(работы.работы)) работы.работы = [];
  // Старую запись СВОЕЙ работы снимаем по номеру. Номера нет (старый вид) —
  // снимаем по роли, но только такую же старую запись без номера: иначе
  // второй параллельный developer стёр бы из списка первого.
  работы.работы = номерАгента
    ? работы.работы.filter((р) => р.задача !== номерАгента)
    : работы.работы.filter((р) => !(р.кто === роль && !р.задача));
  const запись = { что: описание, важность: 'скоро', кто: роль, начато: сейчас };
  if (номерАгента) запись.задача = номерАгента;
  работы.работы.push(запись);
  try { fs.writeFileSync(ФАЙЛ_РАБОТ, JSON.stringify(работы, null, 2) + '\n', 'utf8'); } catch (о) { console.error('в-работе: не удалось записать в-работе.json: ' + о.message); }

  try { execFileSync('node', [path.join(КОРЕНЬ, 'штаб', 'в-работе.js'), '--всё-равно'], { stdio: 'ignore' }); } catch (о) { /* ЗАДАЧИ.md пересоберёт следующий вызов */ }
}

// Запущен напрямую как хук — делаем побочный ход и выходим. Подключён через
// require (так проверяет разовый тест) — никаких файлов не трогаем, отдаём
// наружу только чистые функции извлечьНомерАгента и путиИзСтроки.
if (require.main === module) {
  основнойХод();
  process.exit(0);
} else {
  module.exports = { извлечьНомерАгента: извлечьНомерАгента, путиИзСтроки: путиИзСтроки };
}
