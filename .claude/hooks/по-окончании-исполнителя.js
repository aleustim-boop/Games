// SubagentStop-хук: исполнитель закончил или встал — помечает его запись в
// штаб/права.json полем «завершил» (раньше удалял — теперь только отмечает,
// см. ниже почему), снимает его из штаб/в-работе.json и печатает штабу то же
// системное сообщение, что раньше давал статический echo в settings.local.json.
//
// Почему пометка, а не удаление: штаб часто ВОЗВРАЩАЕТ завершившегося
// исполнителя на следующий шаг тем же номером (SendMessage) — а раньше
// удалённую запись охрана-файлов.js уже не находила по agent_id и шла
// запасным путём «по роли», подхватывая файлы СОВСЕМ ДРУГОГО исполнителя
// той же роли и блокируя правку на его же файлах (было 22.09, дважды).
// Пометка «завершил» вместо delete решает это: охрана по-прежнему находит
// запись возвращённого по номеру (см. охрана-файлов.js), а в запасном пути
// «по роли» такие помеченные записи не участвуют — исключены явно.
//
// Ключ пометки — agent_id (номер), а не роль: 22.09 при остановке одного
// developer снятие «по роли» стёрло из-под охраны второго, ещё работающего
// developer той же роли. По роли помечаем запись/снимаем работу, только
// если она старого вида — без номера внутри (запущена до этой правки хуков).
//
// Чтобы права.json не рос бесконечно мёртвыми записями, при каждом запуске
// хук вычищает записи, помеченные «завершил» больше суток назад.
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..', '..');
const ФАЙЛ_ПРАВ = path.join(КОРЕНЬ, 'штаб', 'права.json');
const ФАЙЛ_РАБОТ = path.join(КОРЕНЬ, 'штаб', 'в-работе.json');
const СУТКИ_МС = 24 * 60 * 60 * 1000;

function читатьВход() {
  let текст = '';
  try { текст = fs.readFileSync(0, 'utf8'); } catch (о) { return null; }
  try { return JSON.parse(текст); } catch (о) { return null; }
}
function читатьJSON(файл, поУмолчанию) {
  try { return JSON.parse(fs.readFileSync(файл, 'utf8')); } catch (о) { return поУмолчанию; }
}
function времяЗаписью(дата) {
  // Тот же формат «YYYY-MM-DD HH:MM», каким начало-исполнителя.js пишет «начал».
  const дв = (ч) => String(ч).padStart(2, '0');
  return дата.getFullYear() + '-' + дв(дата.getMonth() + 1) + '-' + дв(дата.getDate())
    + ' ' + дв(дата.getHours()) + ':' + дв(дата.getMinutes());
}
function разобратьВремя(строка) {
  // Обратное к времяЗаписью — разбираем руками, не полагаясь на то, как
  // new Date() поймёт «YYYY-MM-DD HH:MM» на разных версиях node.
  const совпадение = /^(\d{4})-(\d{2})-(\d{2}) (\d{2}):(\d{2})$/.exec(String(строка || ''));
  if (!совпадение) return null;
  const [, год, месяц, день, час, минута] = совпадение;
  return new Date(Number(год), Number(месяц) - 1, Number(день), Number(час), Number(минута)).getTime();
}

const данные = читатьВход();
const роль = данные && данные.agent_type ? String(данные.agent_type) : null;
const статус = данные && данные.status ? String(данные.status) : 'неизвестно';
const agentIdСырой = данные && данные.agent_id ? String(данные.agent_id) : null;
const agentId = agentIdСырой || '?';

// Читаем права один раз, перед основной логикой
const права = читатьJSON(ФАЙЛ_ПРАВ, {});
const сейчас = времяЗаписью(new Date());

if (роль || agentIdСырой) {
  let помеченоПоНомеру = false;
  if (agentIdСырой && Object.prototype.hasOwnProperty.call(права, agentIdСырой)) {
    права[agentIdСырой].завершил = сейчас;
    помеченоПоНомеру = true;
  }
  // По роли помечаем, только если по номеру не вышло И сама запись
  // роли — старого вида (без номера). Запись с номером принадлежит
  // другому, ещё живому или уже возвращённому исполнителю той же роли —
  // её не трогаем.
  if (!помеченоПоНомеру && роль && права[роль] && !права[роль].номер) {
    права[роль].завершил = сейчас;
  }

  const работы = читатьJSON(ФАЙЛ_РАБОТ, { работы: [] });
  if (!Array.isArray(работы.работы)) работы.работы = [];
  if (agentIdСырой) {
    работы.работы = работы.работы.filter((р) => р.задача !== agentIdСырой);
  }
  if (роль) {
    // Хвосты старого вида (без номера) той же роли — снимаем и их: они
    // могли остаться от запуска до этой правки хуков.
    работы.работы = работы.работы.filter((р) => !(р.кто === роль && !р.задача));
  }
  try { fs.writeFileSync(ФАЙЛ_РАБОТ, JSON.stringify(работы, null, 2) + '\n', 'utf8'); } catch (о) { console.error('в-работе: не удалось обновить в-работе.json: ' + о.message); }

  try { execFileSync('node', [path.join(КОРЕНЬ, 'штаб', 'в-работе.js'), '--всё-равно'], { stdio: 'ignore' }); } catch (о) { /* ЗАДАЧИ.md пересоберёт следующий вызов */ }
}

// Мёртвый груз старше суток — вычищаем, иначе права.json растёт вечно.
// Это выполняется всегда, независимо от наличия роли или agent_id.
for (const ключ of Object.keys(права)) {
  const запись = права[ключ];
  if (запись && запись.завершил) {
    const времяЗавершения = разобратьВремя(запись.завершил);
    if (времяЗавершения !== null && (Date.now() - времяЗавершения) > СУТКИ_МС) {
      delete права[ключ];
    }
  }
}

// Сохраняем обновлённые права один раз, после вычистки
try { fs.writeFileSync(ФАЙЛ_ПРАВ, JSON.stringify(права, null, 2) + '\n', 'utf8'); } catch (о) { console.error('охрана: не удалось обновить права.json: ' + о.message); }

const сообщение = роль
  ? '[ШТАБУ] Исполнитель «' + роль + '» закончил работу или был остановлен (agent_id ' + agentId + ', статус ' + статус + '). Проверить: пришёл ли отчёт, появились ли файлы. Молчание прогрессом не считать.'
  : '[ШТАБУ] Исполнитель закончил работу или был остановлен, роль не распозналась по входу хука. Проверить вручную: пришёл ли отчёт, появились ли файлы.';

console.log(JSON.stringify({ systemMessage: сообщение }));
process.exit(0);
