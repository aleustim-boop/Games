const agentIdВходной = данные.agent_id ? String(данные.agent_id) : '';
const рольВходная = данные.agent_type ? String(данные.agent_type) : '';

// Своя правка штаба: agent_type у главной сессии не бывает. Проверяем ДО
// разбора инструмента — штабу можно всё, вне зависимости от того, чем он
// правит файл.
if (!рольВходная) {
  записатьЖурнал({ agent_id: agentIdВходной || 'нет', роль: '', файл: '', 'чем-нашли': 'штаб', решение: 'пропуск' });
  process.exit(0);
}

// Собираем «сырые» цели правки в зависимости от инструмента. Незнакомый или
// заведомо не пишущий файл инструмент (Read, Grep, Glob, Task…) — решения
// ещё нет, выходим сразу (см. пункт 3 в комментарии наверху файла).
let сырыеЦели = [];
if (ИНСТРУМЕНТЫ_ПРАВКИ.indexOf(инструмент) !== -1) {
  const ф = вход.file_path || (Array.isArray(вход.edits) && вход.edits[0] && вход.edits[0].file_path) || '';
  if (ф) сырыеЦели = [ф];
} else if (ИНСТРУМЕНТЫ_КОМАНДНОЙ_СТРОКИ.indexOf(инструмент) !== -1) {
  сырыеЦели = целиИзКоманды(вход.command || вход.script || '');
} else {
  process.exit(0);
}

if (сырыеЦели.length === 0) process.exit(0); // нечего проверять — решения ещё нет

// Временные пути (Temp/tmp, scratchpad, /dev/null…) и пути вне КОРНЯ проекта —
// не файлы проекта, сверять со списком нечего, пропускаем без прав.json.
const целиВПроекте = [];
for (const сырая of сырыеЦели) {
  // git-bash отдаёт диски как «/d/…» — переводим в «D:/…» ДО обеих проверок
  // ниже, иначе такой путь принимается за «вне корня» и проходит без
  // проверки прав (см. изGitBashПути выше).
  const цель = изGitBashПути(сырая);
  if (похожеНаВременное(цель)) {
    записатьЖурнал({ agent_id: agentIdВходной || 'нет', роль: рольВходная, файл: цель, 'чем-нашли': 'временное', решение: 'пропуск' });
    continue;
  }
  if (путьВнеКорня(цель)) {
    записатьЖурнал({ agent_id: agentIdВходной || 'нет', роль: рольВходная, файл: цель, 'чем-нашли': 'вне-проекта', решение: 'пропуск' });
    continue;
  }
  целиВПроекте.push(цель);
}
if (целиВПроекте.length === 0) process.exit(0); // все цели — временные или вне проекта

let права;
try {
  права = JSON.parse(fs.readFileSync(ФАЙЛ_ПРАВ, 'utf8'));
} catch (о) {
  console.error('охрана-файлов: штаб/права.json нет или не читается — пропускаю без проверки (' + о.message + ')');
  for (const цель of целиВПроекте) записатьЖурнал({ agent_id: agentIdВходной || 'нет', роль: рольВходная, файл: нормализовать(цель), 'чем-нашли': 'нет-записи', решение: 'пропуск' });
  process.exit(0);
}

if (!права || typeof права !== 'object' || Object.keys(права).length === 0) {
  console.error('охрана-файлов: штаб/права.json пуст — пропускаю без проверки, это не повод блокировать всех');
  for (const цель of целиВПроекте) записатьЖурнал({ agent_id: agentIdВходной || 'нет', роль: рольВходная, файл: нормализовать(цель), 'чем-нашли': 'нет-записи', решение: 'пропуск' });
  process.exit(0);
}

// (а) точная запись этого исполнителя по номеру — находит и «возвращённого»
// (запись с полем «завершил»: по-окончании-исполнителя.js её не стирает).
let списокФайлов = null;
let чемНашли = null;
let найденаЗапись = false;
if (agentIdВходной && права[agentIdВходной] && Array.isArray(права[agentIdВходной].файлы)) {
  списокФайлов = права[agentIdВходной].файлы;
  чемНашли = права[agentIdВходной].завершил ? 'номер-возвращённый' : 'номер';
  найденаЗапись = true;
} else {
  // (б) запасной путь — все ЖИВЫЕ записи этой же роли (в том числе старого
  // вида, без номера). Записи с полем «завершил» намеренно исключены: иначе
  // файлы давно завершившихся исполнителей той же роли снова слились бы в
  // один общий список. Одна живая — берём как есть, несколько — объединяем
  // файлы: так честнее, чем гадать, какая из двух параллельных «настоящая».
  const поРоли = Object.keys(права)
    .map((ключ) => права[ключ])
    .filter((з) => з && з.роль === рольВходная && Array.isArray(з.файлы) && !з.завершил);
  if (поРоли.length === 1) {
    списокФайлов = поРоли[0].файлы;
    чемНашли = 'роль';
    найденаЗапись = true;
  } else if (поРоли.length > 1) {
    const объединено = [];
    for (const з of поРоли) {
      for (const ф of з.файлы) if (!объединено.includes(ф)) объединено.push(ф);
    }
    списокФайлов = объединено;
    чемНашли = 'объединение';
    найденаЗапись = true;
  }
}

if (!найденаЗапись) {
  // Ни по номеру, ни по роли записи не нашлось вовсе — это НЕ то же самое,
  // что «запись есть, а список файлов пуст» (см. ниже): например, чужая
  // сессия, которую начало-исполнителя.js вообще не заводил. Блокировать
  // таких подряд — решето хуже дыры, поэтому пропускаем и предупреждаем,
  // как и раньше.
  console.error('охрана-файлов: для роли «' + рольВходная + '» (agent_id ' + (agentIdВходной || '—') + ') в правах нет записи — пропускаю без проверки');
  for (const цель of целиВПроекте) записатьЖурнал({ agent_id: agentIdВходной || 'нет', роль: рольВходная, файл: нормализовать(цель), 'чем-нашли': 'нет-записи', решение: 'пропуск' });
  process.exit(0);
}

if (списокФайлов.length === 0) {
  // Запись НАШЛАСЬ (по номеру или по роли), но список файлов пуст — в
  // задании исполнителя не было строки «Файлы:». Раньше это молча значило
  // «можно всё» (дыра). Теперь — «нельзя ничего в проекте»; временные пути
  // уже пропущены выше, до этого места.
  for (const цель of целиВПроекте) записатьЖурнал({ agent_id: agentIdВходной || 'нет', роль: рольВходная, файл: нормализовать(цель), 'чем-нашли': чемНашли + '-пусто', решение: 'запрет' });
  console.error(
    'охрана-файлов: в задании исполнителя «' + рольВходная + '» нет строки «Файлы:» — правка файлов проекта запрещена. ' +
    'В задании нет строки Файлы: — попросите штаб.'
  );
  process.exit(2);
}

const запрещённые = целиВПроекте.filter((цель) => !списокФайлов.some((маска) => подходит(маска, нормализовать(цель))));
for (const цель of целиВПроекте) {
  const разрешено = списокФайлов.some((маска) => подходит(маска, нормализовать(цель)));
  записатьЖурнал({ agent_id: agentIdВходной || 'нет', роль: рольВходная, файл: нормализовать(цель), 'чем-нашли': чемНашли, решение: разрешено ? 'пропуск' : 'запрет' });
}

if (запрещённые.length > 0) {
  console.error(
    'охрана-файлов: исполнителю «' + рольВходная + '» не разрешён файл «' + запрещённые[0] + '» ' +
    (ИНСТРУМЕНТЫ_КОМАНДНОЙ_СТРОКИ.indexOf(инструмент) !== -1 ? '(похоже, команда пишет в этот файл) ' : '') +
    '(в задании были: ' + списокФайлов.join(', ') + '). ' +
    'Один файл — один исполнитель: если файл правда нужен, остановись и спроси штаб.'
  );
  process.exit(2);
}

process.exit(0);

/** Запись из «Файлы:» может быть точным путём или маской со звёздочкой. */
function подходит(маска, путь) {
  const м = нормализовать(маска);
  if (!м) return false;
  if (!м.includes('*')) return м === путь;
  const кусочки = м.split('*').map((к) => к.replace(/[.+?^${}()|[\]\\]/g, '\\$&'));
  const рег = new RegExp('^' + кусочки.join('.*') + '$');
  return рег.test(путь);
}
