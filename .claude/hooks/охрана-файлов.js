// PreToolUse-хук (matcher "Edit|Write|MultiEdit"): держит «один файл — один
// исполнитель» не только текстом правил, а кодом. Источник правды —
// штаб/права.json, который заводит .claude/hooks/начало-исполнителя.js и
// помечает (не удаляет!) .claude/hooks/по-окончании-исполнителя.js.
//
// Ключ поиска записи — номер исполнителя (agent_id, тот же 16-значный,
// что кладёт начало-исполнителя.js), а не роль: 22.09 штаб запустил двух
// developer параллельно, и охрана по роли заблокировала первого на его же
// файлах. Порядок поиска: (а) права[agent_id] напрямую — работает и для
// «возвращённого» исполнителя: штаб часто зовёт завершившегося на следующий
// шаг тем же номером, а SubagentStop его запись не стирает, только помечает
// полем «завершил» (см. по-окончании-исполнителя.js) — файлы у него те же,
// что были в задании; (б) не нашли по номеру — все ЖИВЫЕ записи с той же
// ролью (agent_type), записи с «завершил» сюда не берём: иначе файлы давно
// ушедших исполнителей той же роли снова слились бы в один список и охрана
// стала бы решетом — ровно та беда, что уже была 22.09, когда записи
// удалялись без разбора при остановке. Ровно одна живая запись — берём её
// файлы, несколько — объединяем списки (не блокируем чужого, но и не
// пускаем куда попало); ни одной — пропуск с предупреждением, как раньше.
// Документация code.claude.com не гарантирует, что agent_id из PreToolUse
// совпадёт по формату с agentId из ответа инструмента Agent — поэтому у
// каждого решения есть запасной путь по роли, а штаб/охрана-журнал.txt (не
// длиннее 200 строк) показывает, каким именно путём хук нашёл запись —
// по нему видно, если номера когда-нибудь разъедутся или возвращённого не
// узнают (в журнале путь «номер-возвращённый» отдельно от простого «номер»).
//
// Своя правка штаба (главная сессия) идёт без agent_type во входе хука —
// такой вызов не трогаем, пропускаем всегда (штабу видно и так, что он делает).
// Пустой или отсутствующий права.json — не блокируем всех подряд (это была бы
// ошибка хуже дыры в правах), а предупреждаем и пропускаем.
//
// Путь вне КОРНЯ проекта (временная папка исполнителя в scratchpad, другой
// диск) — не файл проекта, сверять его со списком не с чем: такую правку
// пропускаем без обращения к правам.json, в журнале это видно как
// «вне-проекта» (см. путьВнеКорня ниже).
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..', '..');
const ФАЙЛ_ПРАВ = path.join(КОРЕНЬ, 'штаб', 'права.json');
const ФАЙЛ_ЖУРНАЛА = path.join(КОРЕНЬ, 'штаб', 'охрана-журнал.txt');
const МАКС_СТРОК_ЖУРНАЛА = 200;

function читатьВход() {
  let текст = '';
  try { текст = fs.readFileSync(0, 'utf8'); } catch (о) { return null; }
  try { return JSON.parse(текст); } catch (о) { return null; }
}

function нормализовать(п) {
  if (!п) return '';
  let полный = path.isAbsolute(п) ? п : path.join(КОРЕНЬ, п);
  return path.relative(КОРЕНЬ, полный).split(path.sep).join('/').toLowerCase();
}

/**
 * Путь за пределами КОРНЯ (например, разовый скрипт в scratchpad исполнителя
 * или файл на другом диске). path.relative в таком случае либо начинается
 * с «..», либо (Windows, разные диски) возвращает уже абсолютный путь —
 * оба случая означают «не файл проекта», сверять со списком нечего.
 */
function путьВнеКорня(файл) {
  if (!файл) return false;
  const полный = path.isAbsolute(файл) ? файл : path.join(КОРЕНЬ, файл);
  const относительный = path.relative(КОРЕНЬ, полный);
  return относительный.startsWith('..') || path.isAbsolute(относительный);
}

/** Запись из «Файлы:» может быть точным путём или маской со звёздочкой. */
function подходит(маска, путь) {
  const м = нормализовать(маска);
  if (!м) return false;
  if (!м.includes('*')) return м === путь;
  const кусочки = м.split('*').map((к) => к.replace(/[.+?^${}()|[\]\\]/g, '\\$&'));
  const рег = new RegExp('^' + кусочки.join('.*') + '$');
  return рег.test(путь);
}

/**
 * Одна строка решения в штаб/охрана-журнал.txt: когда, кто спрашивал, какой
 * файл, каким путём хук нашёл запись и что решил. Журнал — не главное:
 * не записалась строка — решение хука это никак не отменяет.
 */
function записатьЖурнал(поля) {
  const строка = JSON.stringify(Object.assign({ когда: new Date().toISOString() }, поля));
  try {
    let строки = [];
    try { строки = fs.readFileSync(ФАЙЛ_ЖУРНАЛА, 'utf8').split('\n').filter(Boolean); } catch (о) { /* журнала ещё нет — начнём с пустого */ }
    строки.push(строка);
    if (строки.length > МАКС_СТРОК_ЖУРНАЛА) строки = строки.slice(строки.length - МАКС_СТРОК_ЖУРНАЛА);
    fs.writeFileSync(ФАЙЛ_ЖУРНАЛА, строки.join('\n') + '\n', 'utf8');
  } catch (о) { /* не главное */ }
}

const данные = читатьВход();
if (!данные) process.exit(0); // мусор на входе — не рушим хук, пропускаем

const вход = данные.tool_input || {};
const файлПравки = вход.file_path || (Array.isArray(вход.edits) && вход.edits[0] && вход.edits[0].file_path) || '';
const путь = файлПравки ? нормализовать(файлПравки) : '';
const agentIdВходной = данные.agent_id ? String(данные.agent_id) : '';
const рольВходная = данные.agent_type ? String(данные.agent_type) : '';

// Своя правка штаба: agent_type у главной сессии не бывает.
if (!рольВходная) {
  записатьЖурнал({ agent_id: agentIdВходной || 'нет', роль: '', файл: путь || файлПравки, 'чем-нашли': 'штаб', решение: 'пропуск' });
  process.exit(0);
}

if (!файлПравки) process.exit(0); // нечего проверять — не тот инструмент, решения ещё нет

// Файл вне проекта — не с чем сверять список, штаб/права.json тут ни при чём.
if (путьВнеКорня(файлПравки)) {
  записатьЖурнал({ agent_id: agentIdВходной || 'нет', роль: рольВходная, файл: путь || файлПравки, 'чем-нашли': 'вне-проекта', решение: 'пропуск' });
  process.exit(0);
}

let права;
try {
  права = JSON.parse(fs.readFileSync(ФАЙЛ_ПРАВ, 'utf8'));
} catch (о) {
  console.error('охрана-файлов: штаб/права.json нет или не читается — пропускаю без проверки (' + о.message + ')');
  записатьЖурнал({ agent_id: agentIdВходной || 'нет', роль: рольВходная, файл: путь, 'чем-нашли': 'нет-записи', решение: 'пропуск' });
  process.exit(0);
}

if (!права || typeof права !== 'object' || Object.keys(права).length === 0) {
  console.error('охрана-файлов: штаб/права.json пуст — пропускаю без проверки, это не повод блокировать всех');
  записатьЖурнал({ agent_id: agentIdВходной || 'нет', роль: рольВходная, файл: путь, 'чем-нашли': 'нет-записи', решение: 'пропуск' });
  process.exit(0);
}

// (а) точная запись этого исполнителя по номеру — находит и «возвращённого»
// (запись с полем «завершил»: по-окончании-исполнителя.js её не стирает).
let списокФайлов = null;
let чемНашли = null;
if (agentIdВходной && права[agentIdВходной] && Array.isArray(права[agentIdВходной].файлы)) {
  списокФайлов = права[agentIdВходной].файлы;
  чемНашли = права[agentIdВходной].завершил ? 'номер-возвращённый' : 'номер';
} else {
  // (б) запасной путь — все ЖИВЫЕ записи этой же роли (в том числе старого
  // вида, без номера). Записи с полем «завершил» намеренно исключены: иначе
  // файлы давно завершившихся исполнителей той же роли снова слились бы в
  // один общий список. Одна живая — берём как есть, несколько — объединяем
  // файлы: так честнее, чем гадать, какая из двух параллельных «настоящая».
  const поРоли = Object.keys(права)
    .map((ключ) => права[ключ])
    .filter((з) => з && з.роль === рольВходная && Array.isArray(з.файлы) && !з.завершил);
  if (поРоли.length === 1) {
    списокФайлов = поРоли[0].файлы;
    чемНашли = 'роль';
  } else if (поРоли.length > 1) {
    const объединено = [];
    for (const з of поРоли) {
      for (const ф of з.файлы) if (!объединено.includes(ф)) объединено.push(ф);
    }
    списокФайлов = объединено;
    чемНашли = 'объединение';
  }
}

if (!списокФайлов || списокФайлов.length === 0) {
  console.error('охрана-файлов: для роли «' + рольВходная + '» (agent_id ' + (agentIdВходной || '—') + ') в правах нет списка файлов — пропускаю без проверки');
  записатьЖурнал({ agent_id: agentIdВходной || 'нет', роль: рольВходная, файл: путь, 'чем-нашли': 'нет-записи', решение: 'пропуск' });
  process.exit(0);
}

const разрешено = списокФайлов.some((маска) => подходит(маска, путь));
записатьЖурнал({ agent_id: agentIdВходной || 'нет', роль: рольВходная, файл: путь, 'чем-нашли': чемНашли, решение: разрешено ? 'пропуск' : 'запрет' });

if (!разрешено) {
  console.error(
    'охрана-файлов: исполнителю «' + рольВходная + '» не разрешён файл «' + файлПравки + '» ' +
    '(в задании были: ' + списокФайлов.join(', ') + '). ' +
    'Один файл — один исполнитель: если файл правда нужен, остановись и спроси штаб.'
  );
  process.exit(2);
}

process.exit(0);
