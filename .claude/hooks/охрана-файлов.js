// PreToolUse-хук (matcher "Edit|Write|MultiEdit", по-хорошему нужен и
// "Bash|PowerShell" — см. ниже): держит «один файл — один исполнитель» не
// только текстом правил, а кодом. Источник правды — штаб/права.json,
// который заводит .claude/hooks/начало-исполнителя.js и помечает (не
// удаляет!) .claude/hooks/по-окончании-исполнителя.js.
//
// Ключ поиска записи — номер исполнителя (agent_id, тот же 16-значный,
// что кладёт начало-исполнителя.js), а не роль: 22.09 штаб запустил двух
// developer параллельно, и охрана по роли заблокировала первого на его же
// файлах. Порядок поиска: (а) права[agent_id] напрямую — работает и для
// «возвращённого» исполнителя: штаб часто зовёт завершившегося на следующий
// шаг тем же номером, а SubagentStop его запись не стирает, только помечает
// полем «завершил» (см. по-окончании-исполнителя.js) — файлы у него те же,
// что были в задании; (б) не нашли по номеру — все ЖИВЫЕ записи с той же
// ролью (agent_type), записи с «завершил» сюда не берём: иначе файлы давно
// ушедших исполнителей той же роли снова слились бы в один список и охрана
// стала бы решетом — ровно та беда, что уже была 22.09, когда записи
// удалялись без разбора при остановке. Ровно одна живая запись — берём её
// файлы, несколько — объединяем списки (не блокируем чужого, но и не
// пускаем куда попало); ни одной — пропуск с предупреждением, как раньше.
// Документация code.claude.com не гарантирует, что agent_id из PreToolUse
// совпадёт по формату с agentId из ответа инструмента Agent — поэтому у
// каждого решения есть запасной путь по роли, а штаб/охрана-журнал.txt (не
// длиннее 200 строк) показывает, каким именно путём хук нашёл запись —
// по нему видно, если номера когда-нибудь разъедутся или возвращённого не
// узнают (в журнале путь «номер-возвращённый» отдельно от простого «номер»).
//
// Своя правка штаба (главная сессия) идёт без agent_type во входе хука —
// такой вызов не трогаем, пропускаем всегда (штабу видно и так, что он делает).
// Пустой или отсутствующий права.json — не блокируем всех подряд (это была бы
// ошибка хуже дыры в правах), а предупреждаем и пропускаем.
//
// Путь вне КОРНЯ проекта (временная папка исполнителя в scratchpad, другой
// диск) — не файл проекта, сверять его со списком не с чем: такую правку
// пропускаем без обращения к правам.json, в журнале это видно как
// «вне-проекта» (см. путьВнеКорня ниже).
//
// --- Правка 23.09: три дыры ---
// 1) Раньше хук вообще не смотрел на tool_name — только на tool_input.
//    У Bash/PowerShell нет tool_input.file_path, поэтому команда вида
//    «echo подмена > style.css», «sed -i ... style.css», «tee style.css»,
//    «cp/mv … style.css», «Set-Content/Out-File style.css» проходила БЕЗ
//    единой проверки: хук выходил на «нечего проверять» до чтения прав.
//    Теперь хук по tool_name различает Edit/Write/MultiEdit (путь берём как
//    раньше) и Bash/PowerShell (пути ищем в тексте команды регулярками —
//    см. целиИзBashКоманды). Список опознаваемых приёмов сознательно узкий
//    (перенаправление > и >>, sed -i, tee, cp/mv, Set-Content/Out-File) —
//    «поймать всё» невозможно и не требуется, а держать список коротким
//    проще проверить глазами. Запись в matcher settings.json для Bash|
//    PowerShell в этот хук — забота штаба (файл settings.json не в списке
//    файлов этой задачи), без неё код готов, но реально не вызывается для
//    Bash.
// 2) Пустой список «файлы» у НАЙДЕННОЙ записи исполнителя (задание без
//    строки «Файлы:») раньше означало «можно всё» — трактовался как «записи
//    вообще нет». Теперь эти два случая различены явно: «записи нет вовсе»
//    (ни по номеру, ни по роли — например, чужая сессия, не заведённая
//    начало-исполнителя.js) — пропуск, как раньше; «запись есть, а список
//    файлов пуст» — запрет правки файлов проекта (временные пути по-прежнему
//    разрешены) с понятным сообщением «попросите штаб».
// 3) Пустой/битый вход и незнакомый tool_name хук не роняет: непонятный
//    вход — process.exit(0) (пропуск) сразу, до чтения прав.json; тулза не
//    из списка «умеет писать в файл» (Read, Grep, Glob, Task, WebFetch…) —
//    тоже пропуск сразу. Решение осознанное: список «этот инструмент может
//    менять файлы» короткий и явный (Edit/Write/MultiEdit/Bash/PowerShell),
//    добавят новый пишущий инструмент — его придётся вписать сюда самим,
//    зато отказ упасть или заблокировать НЕ из этого списка не остановит
//    работу всей команды на ровном месте. Заблокировать всё «на всякий
//    случай» было бы хуже: одна ошибка в разборе — и встаёт каждый
//    исполнитель на каждом Read/Grep, а это ровно то решето наоборот, от
//    которого предостерегает штаб («ложные запреты хуже пропусков»).
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..', '..');
const ФАЙЛ_ПРАВ = path.join(КОРЕНЬ, 'штаб', 'права.json');
const ФАЙЛ_ЖУРНАЛА = path.join(КОРЕНЬ, 'штаб', 'охрана-журнал.txt');
const МАКС_СТРОК_ЖУРНАЛА = 200;

// Инструменты, которые реально умеют менять содержимое файла. Всё, чего тут
// нет (Read, Grep, Glob, Task, WebFetch, TodoWrite…), для охраны файлов не
// опасно — такие события отсекаются сразу, без обращения к правам.json.
const ИНСТРУМЕНТЫ_ПРАВКИ = ['Edit', 'Write', 'MultiEdit'];
const ИНСТРУМЕНТЫ_КОМАНДНОЙ_СТРОКИ = ['Bash', 'PowerShell'];

function читатьВход() {
  let текст = '';
  try { текст = fs.readFileSync(0, 'utf8'); } catch (о) { return null; }
  try { return JSON.parse(текст); } catch (о) { return null; }
}

function нормализовать(п) {
  if (!п) return '';
  let полный = path.isAbsolute(п) ? п : path.join(КОРЕНЬ, п);
  return path.relative(КОРЕНЬ, полный).split(path.sep).join('/').toLowerCase();
}

/**
 * Путь за пределами КОРНЯ (например, разовый скрипт в scratchpad исполнителя
 * или файл на другом диске). path.relative в таком случае либо начинается
 * с «..», либо (Windows, разные диски) возвращает уже абсолютный путь —
 * оба случая означают «не файл проекта», сверять со списком нечего.
 */
function путьВнеКорня(файл) {
  if (!файл) return false;
  const полный = path.isAbsolute(файл) ? файл : path.join(КОРЕНЬ, файл);
  const относительный = path.relative(КОРЕНЬ, полный);
  return относительный.startsWith('..') || path.isAbsolute(относительный);
}

/**
 * git-bash (POSIX-подобная оболочка Bash на Windows) отдаёт диски в виде
 * «/d/Claud/Games/…» вместо привычного «D:\…». Без перевода путьВнеКорня()
 * принимал ведущую букву диска за первую папку несуществующего корня «/» и
 * решал «путь вне проекта» — правка проходила вовсе без проверки прав.
 * Переводим «/буква/…» в «Буква:/…» ДО всех сравнений с КОРНЕМ. Путь на
 * ЧУЖОМ диске (например «/c/Users/.../Temp/…», когда сам проект лежит на
 * D:) от этого не страдает: после перевода это по-прежнему путь вне КОРНЯ
 * (другой диск) и дальше по коду пропускается как обычно — просто не
 * «нераспознанным мусором», а осознанно.
 */
function изGitBashПути(путь) {
  return String(путь || '').replace(/^\/([a-zA-Z])(\/|$)/, (совпадение, буква, хвост) => буква.toUpperCase() + ':' + хвост);
}

/**
 * Цель Bash/PowerShell-команды «похожа на временную»: переменные окружения
 * $TEMP/%TEMP%/$TMPDIR, ведущий /tmp/ (POSIX-стиль git-bash), приёмник
 * /dev/null или nul, папка scratchpad исполнителя. Проверяем СЫРОЙ текст
 * цели из команды, ДО приведения к КОРНЮ проекта — так ловятся и
 * непереразвёрнутые переменные окружения, которые path.join с КОРНЕМ
 * только испортил бы.
 *
 * Намеренно НЕ ловим общий признак «где-то в пути есть сегмент temp/tmp» —
 * это давало ложные срабатывания: абсолютный путь ВНУТРИ корня проекта
 * тоже может проходить через системную Temp (например, весь проект в тестовой
 * копии физически лежит под os.tmpdir() — так устроена tests/хуки-прав.js).
 * Настоящие временные пути вне проекта (в т.ч. Windows-путь до scratchpad на
 * другом диске) и так поймает путьВнеКорня() ниже по коду — эта функция лишь
 * достаёт случаи, которые путьВнеКорня не распознает как «вне корня» (сырые
 * переменные окружения, ещё не превращённые в путь).
 */
function похожеНаВременное(сырая) {
  if (!сырая) return false;
  let н = String(сырая).toLowerCase();
  if ((н[0] === '"' && н[н.length - 1] === '"') || (н[0] === "'" && н[н.length - 1] === "'")) н = н.slice(1, -1);
  if (н === '/dev/null' || н === 'nul' || н === '\\\\.\\nul') return true;
  if (н === '$null' || н === 'out-null') return true; // PowerShell: > $null, 2>$null, | Out-Null
  if (/^\/tmp\//.test(н) || н === '/tmp') return true; // /tmp/… — POSIX-стиль
  if (/^\$\{?(temp|tmp|tmpdir)\}?([\\/]|$)/i.test(н)) return true; // $TEMP/…, ${TMPDIR}/…
  if (/^%(temp|tmp)%([\\/]|$)/i.test(н)) return true; // %TEMP%\…
  if (н.includes('scratchpad')) return true;
  return false;
}

/** Разбирает токены сегмента команды, сохраняя кавычки как единый токен. */
function токенизировать(строка) {
  const рег = /"[^"]*"|'[^']*'|\S+/g;
  return String(строка || '').match(рег) || [];
}

/** Снимает внешние кавычки с токена. */
function очиститьТокен(токен) {
  if (!токен) return '';
  токен = String(токен).trim();
  if (токен.length >= 2) {
    const первый = токен[0];
    const последний = токен[токен.length - 1];
    if ((первый === '"' && последний === '"') || (первый === "'" && последний === "'")) токен = токен.slice(1, -1);
  }
  return токен;
}

/**
 * Прячет «>» ВНУТРИ одинарных/двойных кавычек (заменяет на «_»), чтобы
 * поиск перенаправления не путал сравнения и текст в кавычках
 * («node -e "if (a > b) x()"», «git commit -m "А > Б"») с настоящей
 * записью в файл. Меняем только сам символ «>» — длина строки и текст
 * ЦЕЛИ перенаправления (если она тоже в кавычках, «> "путь с пробелом.txt"»)
 * не меняются, потому что «>» перед этими кавычками стоит СНАРУЖИ и под
 * маскировку не попадает.
 */
function спрятатьРедиректВКавычках(сегмент) {
  let результат = '';
  let кавычка = null;
  const строка = String(сегмент || '');
  for (let i = 0; i < строка.length; i++) {
    const ч = строка[i];
    if (кавычка) {
      // Внутри ДВОЙНЫХ кавычек «\» экранирует следующий символ (так в bash) —
      // «\"» не закрывает кавычку. Экранированный символ копируем как есть,
      // «>» маскируем и под экранированием (снаружи он всё равно не редирект).
      // Внутри ОДИНАРНЫХ кавычек экранирования нет вовсе — «\» там обычный
      // символ, ветка ниже её не касается.
      if (кавычка === '"' && ч === '\\' && i + 1 < строка.length) {
        результат += ч + (строка[i + 1] === '>' ? '_' : строка[i + 1]);
        i++;
        continue;
      }
      if (ч === кавычка) { кавычка = null; результат += ч; }
      else результат += ч === '>' ? '_' : ч;
    } else {
      if (ч === '"' || ч === "'") кавычка = ч;
      результат += ч;
    }
  }
  return результат;
}

/**
 * Явные записи в файл внутри одного сегмента команды (между &&, ||, |, ;,
 * переносом строки). Ловим только те приёмы, что названы в задаче: «>»,
 * «>>», «&>», «&>>» (с необязательным номером потока перед знаком вроде
 * «2>» или «&» перед знаком для «поток+ошибки в файл»), sed -i, tee, cp/mv
 * (цель — последний аргумент), PowerShell Set-Content/Out-File. Всё, что
 * сюда не попало (например echo без перенаправления, printf в переменную,
 * jq без -i) — сознательно не ловим, это не «правка чужого файла из тени»,
 * а обычный вывод на экран.
 */
function целиИзСегмента(сегмент) {
  const цели = [];
  сегмент = String(сегмент || '');
  if (!сегмент.trim()) return цели;

  // «>» / «>>» / «&>» / «&>>», необязательный номер потока перед знаком
  // («2> файл») ИЛИ «&» перед знаком («&> файл» — вывод и ошибки разом),
  // «>=» не трогаем (не redirection). Ищем по тексту с «спрятанными»
  // кавычками — иначе «>» внутри строкового литерала ловится как редирект.
  const дляПоиска = спрятатьРедиректВКавычках(сегмент);
  const РЕДИРЕКТ = /(?:^|[\s(])(?:\d{0,2}|&)(>>?)(?!=)\s*("[^"]*"|'[^']*'|\S+)/g;
  let совпадение;
  while ((совпадение = РЕДИРЕКТ.exec(дляПоиска))) {
    const цель = очиститьТокен(совпадение[2]);
    if (цель && !цель.startsWith('&') && !/^\d+$/.test(цель)) цели.push(цель);
  }

  // sed -i / --in-place правит файл на месте — цель обычно последний аргумент.
  if (/\bsed\b/.test(сегмент) && /(^|\s)(-[a-zA-Z]*i[a-zA-Z]*\S*|--in-place\S*)(\s|$)/.test(сегмент)) {
    const токены = токенизировать(сегмент).map(очиститьТокен);
    if (токены.length) цели.push(токены[токены.length - 1]);
  }

  // tee [-a] файл — печатает и одновременно пишет в файл.
  const teeСовп = /\btee\b\s+(?:-a\s+)?("[^"]*"|'[^']*'|\S+)/.exec(сегмент);
  if (teeСовп) цели.push(очиститьТокен(teeСовп[1]));

  // cp/mv источник назначение — берём последний токен как назначение.
  if (/(^|\s)(cp|mv)\s/.test(сегмент)) {
    const токены = токенизировать(сегмент).map(очиститьТокен);
    if (токены.length >= 3) цели.push(токены[токены.length - 1]);
  }

  // PowerShell Set-Content / Out-File.
  const psСовп = /\b(Set-Content|Out-File)\b\s+(?:-(?:Path|FilePath)\s+)?("[^"]*"|'[^']*'|\S+)/i.exec(сегмент);
  if (psСовп) цели.push(очиститьТокен(psСовп[2]));

  return цели.filter(Boolean);
}

/**
 * Вырезает ТЕЛО heredoc (строки между «<<МЕТКА»/«<<'МЕТКА'»/«<<"МЕТКА»/
 * «<<-МЕТКА» и строкой, где после пробелов стоит ровно МЕТКА) из текста
 * команды. Без этого разбор по переводу строки ниже принимает тело за
 * отдельные команды: `cat > файл <<'EOF'` с телом `> Это цитата` даёт
 * «ложную» цель записи «Это» — хук запрещает то, что на самом деле просто
 * текст будущего файла. Саму строку-открытие (с «cat > файл») и
 * строку-метку в конце оставляем как есть — цель самого cat проверяется
 * как обычно, именно ей и положено попасть в цели.
 */
function убратьТелаHeredoc(команда) {
  const строки = String(команда || '').split('\n');
  const результат = [];
  let метка = null; // пока не null — идём по телу heredoc и строки выбрасываем
  const регОткрытие = /<<-?\s*(['"]?)([A-Za-z_][\w]*)\1/;
  for (const строка of строки) {
    if (метка !== null) {
      if (строка.trim() === метка) { метка = null; результат.push(строка); }
      continue; // строка тела heredoc — не команда, в разбор не идёт
    }
    результат.push(строка);
    const совпадение = регОткрытие.exec(строка);
    if (совпадение) метка = совпадение[2];
  }
  return результат.join('\n');
}

/** Все цели записи из целой Bash/PowerShell-команды, без повторов. */
function целиИзКоманды(команда) {
  const безТелHeredoc = убратьТелаHeredoc(команда);
  const сегменты = String(безТелHeredoc || '').split(/&&|\|\||[|;\n]/);
  const все = [];
  for (const сегмент of сегменты) {
    for (const цель of целиИзСегмента(сегмент)) if (!все.includes(цель)) все.push(цель);
  }
  return все;
}

/**
 * Одна строка решения в штаб/охрана-журнал.txt: когда, кто спрашивал, какой
 * файл, каким путём хук нашёл запись и что решил. Журнал — не главное:
 * не записалась строка — решение хука это никак не отменяет.
 */
function записатьЖурнал(поля) {
  const строка = JSON.stringify(Object.assign({ когда: new Date().toISOString() }, поля));
  try {
    let строки = [];
    try { строки = fs.readFileSync(ФАЙЛ_ЖУРНАЛА, 'utf8').split('\n').filter(Boolean); } catch (о) { /* журнала ещё нет — начнём с пустого */ }
    строки.push(строка);
    if (строки.length > МАКС_СТРОК_ЖУРНАЛА) строки = строки.slice(строки.length - МАКС_СТРОК_ЖУРНАЛА);
    fs.writeFileSync(ФАЙЛ_ЖУРНАЛА, строки.join('\n') + '\n', 'utf8');
  } catch (о) { /* не главное */ }
}

const данные = читатьВход();
