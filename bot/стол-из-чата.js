/* Стол из чата: команда /играть прямо в групповом чате.

   Зачем. Люди сидят в общих чатах. Раньше, чтобы позвать друзей, надо было
   открыть игру, создать стол, нажать «Позвать друга» и выбрать чат — четыре
   шага. Теперь один: написать в чат /играть. Бот сам создаёт стол на сервере
   комнат и кладёт в чат сообщение с кнопкой «Сесть за стол». Кто нажал —
   тот сел. В личной переписке команда делает то же самое: просто стол.

   Кто хозяин стола. Сервер сажает создателя комнаты первым и делает его
   хозяином — только хозяин нажимает «Начать». Создаёт комнату бот, а играть
   он не будет, и отдать место человеку через ссылку нельзя: ссылка несёт
   только код комнаты. Поэтому бот поступает так:
     1. садится за стол сам, под именем «Бот-зазывала», и держит стол —
        спрашивает у сервера новости (длинный опрос /что-нового);
     2. как только за стол сел первый живой человек — бот выходит (/выйти).
        Сервер при выходе хозяина отдаёт хозяйство живому человеку на связи
        (см. передатьХозяина в server/комнаты.js), а место бота освобождается;
     3. никто не сел за десять минут — бот выходит из пустой комнаты, сервер
        её тут же убирает, а бот правит сообщение в чате: «стол закрылся».
        Мёртвой кнопки в чате не остаётся.
   Так хозяином становится тот, кто сел первым, — обычно тот, кто и звал.
   Сервер править не пришлось.

   Стол создаётся «на компанию» (шесть мест, с прихожей и кнопкой «Начать»),
   а не на двоих: комната на двоих раздаёт карты сама, как только вошёл
   второй, — и партия началась бы с призраком-зазывалой.

   Какая кнопка. Особую кнопку «открыть игру» (web_app) Telegram разрешает
   только в личной переписке с ботом — в группе она не работает. Обычная
   ссылка на мини-приложение t.me/БОТ/BoardGames?startapp=КОД-адрес работает
   везде: игра читает из неё код комнаты и адрес сервера (адрес едет в виде
   base64url — см. разобратьПриглашение в js/сеть.js). Ссылку собираем ровно
   в том виде, в каком её собирает сама игра.

   Не спамить: один человек — не чаще одного стола в минуту, и всего
   открытых столов не больше двадцати. Брошенные комнаты сервер убирает сам. */

'use strict';

/* Сколько держим стол открытым, если никто не садится. Десять минут:
   в общем чате сообщение читают не сразу, а дольше держать призрака
   на сервере незачем. */
const ЖДЁМ_ГОСТЕЙ = 10 * 60 * 1000;

/* Один человек — один стол в минуту. Кнопка «/играть» нажимается легко,
   а каждый стол — это комната на сервере. */
const ОДИН_СТОЛ_В = 60 * 1000;

/* Больше стольких открытых столов разом бот не держит: каждый — это
   один висящий запрос к серверу. Для домашнего сервера двадцати с запасом. */
const ПОТОЛОК_ОТКРЫТЫХ = 20;

/* Мест за столом из чата: максимум, какой умеет игра. Хозяин в прихожей
   может убавить. */
const МЕСТ_ЗА_СТОЛОМ = 6;

/* Как бот подписан за столом, пока держит место. Имя видно человеку
   секунду — и в строке «Бот-зазывала выходит из комнаты». */
const ИМЯ_ЗАЗЫВАЛЫ = 'Бот-зазывала';

const СОЗДАНИЕ_ЖДЁТ = 5000;    // столько ждём ответа на «создать» и «выйти»
const ОПРОС_ЖДЁТ = 65000;      // дольше, чем сервер держит длинный опрос (до 60 с)
const ПЕРЕДЫШКА = 3000;        // пауза перед повтором, если связь с сервером сорвалась

/** Адрес сервера буквами, которые разрешены в ссылке мини-приложения
    (латиница, цифры, «-» и «_»). Ровно то же, что делает игра в
    буквамиИзАдреса: base64 от байтов адреса, только с безопасными знаками. */
function буквамиИзАдреса(адрес) {
  return Buffer.from(String(адрес || ''), 'utf8').toString('base64')
    .replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
}

/** Ссылка, ведущая прямо за стол: игра откроется внутри Telegram и сама
    войдёт в комнату по коду. Разделитель между кодом и адресом — первый «-»:
    в кодах комнат его не бывает. */
function ссылкаЗаСтол(имяБота, короткоеИмя, код, адресСервера) {
  return 'https://t.me/' + имяБота + '/' + короткоеИмя +
    '?startapp=' + код + '-' + буквамиИзАдреса(адресСервера);
}

/** Сел ли за стол кто-то, кроме самого бота. Смотрим список сидящих
    (в комнате на компанию он есть всегда); на всякий случай понимаем
    и старый признак «соперник пришёл». */
function ктоТоСел(состояние) {
  if (!состояние || typeof состояние !== 'object') return false;
  if (Array.isArray(состояние.застолом)) {
    return состояние.застолом.some(function (место) {
      return место && !место.этоЯ && !место.этоБот && !место.ушёл;
    });
  }
  return состояние.соперникПришёл === true;
}

function минут(миллисекунды) {
  return Math.max(1, Math.round(миллисекунды / 60000));
}

/** Собираем стол из чата. Всё, что ходит наружу, приходит извне —
    так модуль проверяется без Telegram и без сервера:
      вызовAPI(метод, данные)                     — запрос к Telegram
      запросКСерверу(адрес, путь, тело, ждать)   — запрос к серверу комнат
      адресСервера()                              — откуда взять адрес сервера
      имяБота()                                   — @имя бота для ссылки
      короткоеИмя                                 — имя мини-приложения
      отметитьВызов(номер, изГруппы)              — запись в статистику
    Необязательные (для проверок): ждёмГостей, одинСтолВ, пауза, сейчас, сказать. */
function создать(зависимости) {
  const з = зависимости || {};
  const ждёмГостей = з.ждёмГостей || ЖДЁМ_ГОСТЕЙ;
  const одинСтолВ = з.одинСтолВ || ОДИН_СТОЛ_В;
  const пауза = з.пауза || function (мс) { return new Promise(function (р) { setTimeout(р, мс); }); };
  const сейчас = з.сейчас || function () { return Date.now(); };
  const сказать = з.сказать || function (текст) { console.error(текст); };

  const последнийСтол = new Map();   // номер человека → когда он открывал стол
  const открытые = new Map();        // код комнаты → стол, который бот сейчас держит

  function ответить(чатId, текст, кнопки) {
    const данные = { chat_id: чатId, text: текст };
    if (кнопки) данные.reply_markup = кнопки;
    return з.вызовAPI('sendMessage', данные);
  }

  /** Команда /играть пришла. Создаём стол и кладём в чат кнопку. */
  async function позватьКСтолу(сообщение) {
    const чат = сообщение.chat || {};
    const кто = сообщение.from || {};
    if (!кто.id || кто.is_bot) return;
    const изГруппы = чат.type !== 'private';

    const адрес = з.адресСервера();
    if (!адрес) {
      await ответить(чат.id, 'Стол из чата пока не настроен: боту не задан адрес сервера комнат.');
      return;
    }

    const прошлыйРаз = последнийСтол.get(кто.id);
    if (прошлыйРаз && сейчас() - прошлыйРаз < одинСтолВ) {
      await ответить(чат.id, 'Стол для вас уже открыт — он чуть выше в чате. Новый можно открыть через минуту.');
      return;
    }
    if (открытые.size >= ПОТОЛОК_ОТКРЫТЫХ) {
      await ответить(чат.id, 'Сейчас открыто слишком много столов. Попробуйте через минуту.');
      return;
    }

    const ответ = await з.запросКСерверу(адрес, '/создать',
      { мест: МЕСТ_ЗА_СТОЛОМ, имя: ИМЯ_ЗАЗЫВАЛЫ }, СОЗДАНИЕ_ЖДЁТ);

    // Сервер молчит — говорим прямо и ссылки не даём: битая кнопка хуже отказа
    if (!ответ) {
      await ответить(чат.id, 'Сервер игры сейчас не отвечает, попробуйте позже.');
      return;
    }
    const данные = ответ.данные || {};
    if (!ответ.ок || !данные.код || !данные.пропуск) {
      const почему = typeof данные.ошибка === 'string' ? данные.ошибка : '';
      await ответить(чат.id, почему
        ? 'Стол открыть не вышло: ' + почему
        : 'Стол открыть не вышло — сервер игры ответил непонятно. Попробуйте позже.');
      return;
    }

    последнийСтол.set(кто.id, сейчас());
    const стол = {
      код: данные.код,
      пропуск: данные.пропуск,
      версия: (данные.состояние && данные.состояние.версия) || 1,
      адрес: адрес,
      чат: чат.id,
      сообщение: null
    };

    const ссылка = ссылкаЗаСтол(з.имяБота(), з.короткоеИмя, стол.код, адрес);
    const имя = (кто.first_name || '').trim() || 'Кто-то';
    /* Здесь игру называем прямо — и это тот самый случай, когда так и надо:
       стол уже создан, и он дуракский. Обещаем только то, что правда: мест
       столько-то, первый севший распоряжается столом, ждём столько-то минут. */
    const текст = имя + ' зовёт за стол в подкидного дурака!\n\n' +
      'Нажмите кнопку — и вы за столом. Мест ' + МЕСТ_ЗА_СТОЛОМ + ', ' +
      'кто сел первым — тот и начинает партию.\n' +
      'Стол ждёт ' + минут(ждёмГостей) + ' минут.';

    let отправлено;
    try {
      отправлено = await ответить(чат.id, текст, {
        inline_keyboard: [[{ text: 'Сесть за стол', url: ссылка }]]
      });
    } catch (сбой) {
      // Сообщение в чат не ушло — стол никому не достанется, закрываем сразу
      await з.запросКСерверу(адрес, '/выйти', { код: стол.код, пропуск: стол.пропуск }, СОЗДАНИЕ_ЖДЁТ);
      throw сбой;
    }
    стол.сообщение = отправлено && отправлено.message_id ? отправлено.message_id : null;

    з.отметитьВызов(кто.id, изГруппы);

    // Сторож работает сам по себе: бот тем временем отвечает другим
    открытые.set(стол.код, стол);
    следитьЗаСтолом(стол)
      .catch(function (сбой) { сказать('Сторож стола ' + стол.код + ' упал: ' + сбой.message); })
      .then(function () { открытые.delete(стол.код); });
  }

  /** Держим стол, пока не сядет первый живой человек или не выйдет время. */
  async function следитьЗаСтолом(стол) {
    const крайнийСрок = сейчас() + ждёмГостей;
    let версия = стол.версия;
    let гостиПришли = false;
    let комнатыНет = false;

    while (сейчас() < крайнийСрок) {
      const начало = сейчас();
      const ответ = await з.запросКСерверу(стол.адрес, '/что-нового',
        { код: стол.код, пропуск: стол.пропуск, версия: версия }, ОПРОС_ЖДЁТ);

      // Связь сорвалась или сервер (туннель) ответил сбоем — переждём и снова
      if (!ответ || ответ.номер >= 500) {
        await пауза(ПЕРЕДЫШКА);
        continue;
      }
      // 404 — комнаты уже нет (сервер перезапустили или убрал её сам)
      if (!ответ.ок) {
        комнатыНет = true;
        break;
      }
      const новости = ответ.данные || {};
      if (новости.комнатыНет) {
        комнатыНет = true;
        break;
      }
      if (новости.изменилось && новости.состояние) {
        версия = новости.состояние.версия || версия;
        if (ктоТоСел(новости.состояние) ||
            (новости.состояние.этап && новости.состояние.этап !== 'ожидание')) {
          гостиПришли = true;
          break;
        }
      }
      // Сервер ответил мгновенно и без новостей — не крутимся впустую
      if (сейчас() - начало < 1000) await пауза(1000);
    }

    /* Выходим из-за стола в обоих случаях. Сел человек — хозяйство уходит
       ему, а место бота освобождается. Не сел никто — комната пустеет,
       и сервер её убирает сразу. */
    if (!комнатыНет) {
      await з.запросКСерверу(стол.адрес, '/выйти', { код: стол.код, пропуск: стол.пропуск }, СОЗДАНИЕ_ЖДЁТ);
    }
    if (гостиПришли || !стол.сообщение) return;

    // Никто не сел — в чате не должно остаться кнопки в никуда
    try {
      await з.вызовAPI('editMessageText', {
        chat_id: стол.чат,
        message_id: стол.сообщение,
        text: 'Стол закрылся: за ' + минут(ждёмГостей) + ' минут никто не сел. ' +
          'Напишите /играть — откроем новый.'
      });
    } catch (сбой) {
      /* сообщение могли удалить из чата — тогда и править нечего */
    }
  }

  return {
    позватьКСтолу: позватьКСтолу,
    открытыхСтолов: function () { return открытые.size; }
  };
}

module.exports = {
  создать: создать,
  ссылкаЗаСтол: ссылкаЗаСтол,
  буквамиИзАдреса: буквамиИзАдреса,
  ктоТоСел: ктоТоСел,
  ЖДЁМ_ГОСТЕЙ: ЖДЁМ_ГОСТЕЙ,
  ОДИН_СТОЛ_В: ОДИН_СТОЛ_В,
  ПОТОЛОК_ОТКРЫТЫХ: ПОТОЛОК_ОТКРЫТЫХ,
  МЕСТ_ЗА_СТОЛОМ: МЕСТ_ЗА_СТОЛОМ,
  ИМЯ_ЗАЗЫВАЛЫ: ИМЯ_ЗАЗЫВАЛЫ
};
