/** Сводка сервера за окно — в той форме, в какой её отдаёт GET /статистика. */
function сводкаСервера(людей, начато, доиграно, брошено, сЛюдьми, поПриглашению) {
  return {
    комнатСоздано: начато + 1,
    партийНачато: начато,
    партийДоиграно: доиграно,
    партийБрошено: брошено,
    партийСБотами: начато - сЛюдьми,
    партийСЛюдьми: сЛюдьми,
    партийПарами: 0,
    селиПоПриглашению: поПриглашению,
    людей: людей
  };
}
const ответСервера = {
  день: цифры.день,
  хранимДней: 60,
  сегодня: сводкаСервера(4, 6, 5, 1, 2, 1),
  дней7: сводкаСервера(9, 31, 23, 6, 12, 3),
  дней30: сводкаСервера(20, 80, 70, 10, 30, 5)
};
const молчит = 'Сервер комнат не отвечает — партии за сегодня неизвестны.';

