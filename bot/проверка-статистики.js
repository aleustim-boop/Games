проверить('неделя: живые люди и приглашения',
  сСервером.indexOf('с живыми людьми — 12, с ботом — 19; по приглашению друга сели 3 раза.') !== -1, true);
проверить('сегодня: «1 раз» склоняется верно',
  сСервером.indexOf('по приглашению друга сели 1 раз.') !== -1, true);
проверить('цифры бота при этом на месте', сСервером.indexOf('За неделю заходили') !== -1, true);
