// №2 дважды открывал приглашение и один раз отправил; №3 только открыл
счётчик.отметитьПриглашение({ номер: 2, отправлено: false, когда: днейНазад(0) });
счётчик.отметитьПриглашение({ номер: 2, отправлено: false, когда: днейНазад(0) });
счётчик.отметитьПриглашение({ номер: 2, отправлено: true, когда: днейНазад(0) });
счётчик.отметитьПриглашение({ номер: 3, отправлено: false, когда: днейНазад(0) });
// Человек, которого в счёте ещё не было, тоже не теряется
счётчик.отметитьПриглашение({ номер: 6, отправлено: false, когда: днейНазад(0) });

