/* Проверка счётчика статистики — без Telegram и без живого бота.

   Запуск:  node bot/проверка-статистики.js

   Работает во временной папке операционной системы, поэтому настоящие данные
   бота (bot/данные/статистика.json) она не трогает и испортить не может.

   Проверяем главное:
     — что числа считаются верно (новые, вернувшиеся, окна 7 и 30 дней);
     — что записанное переживает перезапуск бота;
     — что испорченный файл не роняет бота, а откладывается в сторону;
     — что после записи не остаётся мусорного временного файла. */

'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');

const Статистика = require('./статистика.js');

let всегоПроверок = 0;
let провалов = 0;

/** Одна проверка: что ожидали и что получилось. */
function проверить(описание, получилось, ожидалось) {
  всегоПроверок += 1;
  const сошлось = JSON.stringify(получилось) === JSON.stringify(ожидалось);
  if (сошлось) {
    console.log('  ок   — ' + описание);
  } else {
    провалов += 1;
    console.log('  СБОЙ — ' + описание);
    console.log('         ожидали: ' + JSON.stringify(ожидалось));
    console.log('         вышло:   ' + JSON.stringify(получилось));
  }
}

/** Временная папка под этот прогон. */
const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'проверка-статистики-'));
const файл = path.join(папка, 'статистика.json');

/** Дата-помощница: «столько-то дней назад в полдень». */
function днейНазад(сколько) {
  const дата = new Date();
  дата.setHours(12, 0, 0, 0);
  дата.setDate(дата.getDate() - сколько);
  return дата;
}

console.log('');
console.log('Папка прогона: ' + папка);
console.log('');
console.log('1. Считаем людей и дни');

let счётчик = Статистика.создатьСчётчик({ файл: файл, молча: true });

// Человек №1: пришёл 10 дней назад и с тех пор не появлялся
счётчик.отметитьЗаход({ номер: 1, источник: 'прямая', когда: днейНазад(10) });

// Человек №2: пришёл 3 дня назад, заходил ещё вчера и сегодня (дважды)
счётчик.отметитьЗаход({ номер: 2, источник: 'приглашение', когда: днейНазад(3) });
счётчик.отметитьЗаход({ номер: 2, источник: 'приглашение', когда: днейНазад(1) });
счётчик.отметитьЗаход({ номер: 2, источник: 'приглашение', когда: днейНазад(0) });
счётчик.отметитьЗаход({ номер: 2, источник: 'приглашение', когда: днейНазад(0) });

// Человек №3: пришёл сегодня впервые
счётчик.отметитьЗаход({ номер: 3, источник: 'группа', когда: днейНазад(0) });

// Человек №4: пришёл 40 дней назад — старше всех окон
счётчик.отметитьЗаход({ номер: 4, источник: 'прямая', когда: днейНазад(40) });

let цифры = счётчик.цифры();

проверить('всего людей — 4', цифры.всегоЛюдей, 4);
проверить('обращений всего — 7', цифры.всегоОбращений, 7);
проверить('сегодня заходили двое (№2 и №3)', цифры.сегодня, 2);
проверить('из них новый один (№3)', цифры.новыхСегодня, 1);
проверить('вернувшийся сегодня один (№2)', цифры.вернувшихсяСегодня, 1);
проверить('за неделю заходили двое', цифры.заНеделю, 2);
проверить('за неделю новых двое (оба пришли впервые внутри недели)', цифры.новыхЗаНеделю, 2);
проверить('за 30 дней заходили трое (№1, №2, №3)', цифры.заМесяц, 3);
проверить('приходили больше одного дня — только №2', цифры.приходилиБольшеОдногоДня, 1);
проверить('источник «приглашение» — один человек', цифры.источники.приглашение, 1);
проверить('источник «прямая» — двое', цифры.источники.прямая, 2);
проверить('про партии бот честно ничего не знает', цифры.игра, null);

console.log('');
console.log('2. Запись переживает перезапуск бота');

проверить('сохранение прошло', счётчик.сохранить(), true);
проверить('файл появился на диске', fs.existsSync(файл), true);
проверить('мусорного временного файла не осталось', fs.existsSync(файл + '.новая'), false);

// Перезапуск бота — это просто новый счётчик из того же файла
const послеПерезапуска = Статистика.создатьСчётчик({ файл: файл, молча: true });
const цифрыПосле = послеПерезапуска.цифры();

проверить('после перезапуска столько же людей', цифрыПосле.всегоЛюдей, цифры.всегоЛюдей);
проверить('после перезапуска столько же обращений', цифрыПосле.всегоОбращений, цифры.всегоОбращений);
проверить('после перезапуска та же возвращаемость',
  цифрыПосле.приходилиБольшеОдногоДня, цифры.приходилиБольшеОдногоДня);

// И счёт продолжается с того же места, а не с нуля
послеПерезапуска.отметитьЗаход({ номер: 5, источник: 'прямая', когда: днейНазад(0) });
проверить('новый человек добавился к прежним', послеПерезапуска.цифры().всегоЛюдей, 5);
послеПерезапуска.сохранить();

console.log('');
console.log('3. Бота убили посреди записи');

// Смоделируем след недописанного файла: рядом лежит обрывок «.новая»
fs.writeFileSync(файл + '.новая', '{ "люди": { "999": ', 'utf8');
const послеУбийства = Статистика.создатьСчётчик({ файл: файл, молча: true });
проверить('обрывок не мешает: данные целы', послеУбийства.цифры().всегоЛюдей, 5);
проверить('и не считается за человека', послеУбийства.цифры().всегоЛюдей !== 6, true);
послеУбийства.сохранить();
проверить('новая запись затёрла обрывок', fs.existsSync(файл + '.новая'), false);

console.log('');
console.log('4. Файл статистики испорчен');

fs.writeFileSync(файл, 'это не JSON, а мусор', 'utf8');
const послеПорчи = Статистика.создатьСчётчик({ файл: файл, молча: true });
проверить('бот не упал, счёт начат заново', послеПорчи.цифры().всегоЛюдей, 0);
const битые = fs.readdirSync(папка).filter(function (имя) { return имя.indexOf('.битый-') !== -1; });
проверить('испорченный файл отложен в сторону, а не удалён', битые.length, 1);
послеПорчи.отметитьЗаход({ номер: 7, источник: 'прямая' });
проверить('после порчи счёт снова идёт', послеПорчи.цифры().всегоЛюдей, 1);

console.log('');
console.log('5. Отчёт человеческими словами');

const отчёт = Статистика.текстОтчёта(цифры);
проверить('в отчёте есть строка про неделю', отчёт.indexOf('За неделю заходили') !== -1, true);
проверить('в отчёте есть возвращаемость', отчёт.indexOf('больше одного дня') !== -1, true);
проверить('в отчёте правильное окончание слова «человека»',
  отчёт.indexOf('2 человека') !== -1, true);
проверить('пустой отчёт понятен',
  Статистика.текстОтчёта({ всегоЛюдей: 0 }).indexOf('не обращался никто') !== -1, true);

console.log('');
console.log('Вот как отчёт выглядит целиком:');
console.log('---');
console.log(отчёт);
console.log('---');

console.log('');
console.log('Проверок: ' + всегоПроверок + ', неудачных: ' + провалов);
console.log('Папку прогона можно удалить: ' + папка);
console.log('');

process.exit(провалов ? 1 : 0);
