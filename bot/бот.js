/** Откуда пришёл человек — определяем по самому сообщению.
    В личной переписке смотрим на хвостик команды /start: если игрок пришёл
    по ссылке-приглашению вида t.me/бот?start=метка, Telegram кладёт метку
    сюда же, в текст. Пустой хвостик — значит открыл бота напрямую. */
function откудаПришёл(сообщение) {
  const чат = сообщение.chat || {};
  if (чат.type !== 'private') return Статистика.ИСТОЧНИКИ.группа;

  const текст = (сообщение.text || '').trim();
  const начало = /^\/start(@\S+)?(\s+(\S+))?$/.exec(текст);
  if (начало && начало[3]) return Статистика.ИСТОЧНИКИ.приглашение;

  return Статистика.ИСТОЧНИКИ.прямая;
}

