/** Разбираем файл настроек: строки вида ИМЯ=значение, строки с # — пояснения. */
function прочитатьНастройки(файл) {
  const настройки = {};
  const строки = fs.readFileSync(файл, 'utf8').split(/\r?\n/);

  for (const строка of строки) {
    const чистая = строка.trim();
    if (!чистая || чистая.startsWith('#')) continue;

    const место = чистая.indexOf('=');
    if (место === -1) continue;

    const имя = чистая.slice(0, место).trim();
    let значение = чистая.slice(место + 1).trim();
    // Кавычки вокруг значения убираем: их часто копируют вместе с токеном
    const первый = значение.charAt(0);
    const последний = значение.charAt(значение.length - 1);
    if (значение.length > 1 && первый === последний && (первый === '"' || первый === "'")) {
      значение = значение.slice(1, -1);
    }
    настройки[имя] = значение;
  }
  return настройки;
}

