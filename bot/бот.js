/* Бот-лаунчер: показывает в Telegram кнопку «Играть», которая открывает игру.

   Что он умеет и больше ничего:
     — на команду /start (и на любое сообщение) отвечает приветствием
       с кнопкой «Играть» и кнопкой «Позвать друга»;
     — «Позвать друга» открывает список чатов Telegram, и бот присылает туда
       готовое приглашение. Настоящей игры вдвоём по сети у нас нет —
       это именно приглашение попробовать.

   Написан на том, что уже есть в Node.js: никаких библиотек и установок.
   Настройки (токен и адрес игры) читаются только из файла bot/.env,
   который в репозиторий не попадает.

   Запуск:  node bot/бот.js      Остановка: Ctrl+C */

'use strict';

const fs = require('fs');
const path = require('path');
const https = require('https');

const ФАЙЛ_НАСТРОЕК = path.join(__dirname, '.env');
const ФАЙЛ_ОБРАЗЦА = path.join(__dirname, '.env.example');

// ---------------------------------------------------------------------------
// Настройки: читаем bot/.env
// ---------------------------------------------------------------------------

/** Разбираем файл настроек: строки вида ИМЯ=значение, строки с # — пояснения. */
function прочитатьНастройки(файл) {
  const настройки = {};
  const строки = fs.readFileSync(файл, 'utf8').split(/\r?\n/);

  for (const строка of строки) {
    const чистая = строка.trim();
    if (!чистая || чистая.startsWith('#')) continue;

    const место = чистая.indexOf('=');
    if (место === -1) continue;

    const имя = чистая.slice(0, место).trim();
    let значение = чистая.slice(место + 1).trim();
    // Кавычки вокруг значения убираем: их часто копируют вместе с токеном
    const первый = значение.charAt(0);
    const последний = значение.charAt(значение.length - 1);
    if (значение.length > 1 && первый === последний && (первый === '"' || первый === "'")) {
      значение = значение.slice(1, -1);
    }
    настройки[имя] = значение;
  }
  return настройки;
}

/** Понятно объясняем, что не так, и выходим — без непонятных красных простыней. */
function остановитьсяСОбъяснением(строки) {
  console.error('');
  for (const строка of строки) console.error(строка);
  console.error('');
  process.exit(1);
}

