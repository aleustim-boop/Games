/** Какой адрес сервера комнат зашит в хвостик адреса игры: «?сервер=…».
    Игра внутри Telegram берёт адрес сервера только оттуда — руками в
    Telegram ссылку не поправишь. Нет хвостика — вдвоём не сыграть.
    Возвращаем адрес сервера или пустую строку. */
function адресСервераИзАдресаИгры(адресИгры) {
  try {
    const разбор = new URL(адресИгры);
    // Русское имя удобно человеку, латинское — тому, кто правит настройки
    // в консоли. Игра принимает оба, значит и проверяем оба.
    return (разбор.searchParams.get('сервер') || разбор.searchParams.get('server') || '').trim();
  } catch (сбой) {
    return '';
  }
}

