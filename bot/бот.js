async function работать() {
  const имяБота = await узнатьИмяБота();
  const бедаСКнопкойМеню = await поставитьКнопкуМеню();

  console.log('');
  console.log('Бот запущен: @' + имяБота);
  console.log('Адрес игры:  ' + НАСТРОЙКИ.адресИгры);

  if (бедаСКнопкойМеню) {
    console.log('Постоянной кнопки «Играть» рядом с полем ввода не будет: ' + бедаСКнопкойМеню);
    console.log('Это не поломка — игра открывается кнопкой в ответе на /start.');
  } else {
    console.log('Кнопка «Играть» стоит рядом с полем ввода — её видно всегда.');
  }

  рассказатьПроСерверКомнат();
  рассказатьПроСтатистику();

  console.log('');
  console.log('Напишите боту /start в Telegram. Остановить бота — Ctrl+C.');
  console.log('');

  let следующее = 0;   // номер, начиная с которого спрашиваем новости

  while (true) {
    let новости;
    try {
      новости = await вызовAPI('getUpdates', {
        offset: следующее,
        timeout: 30,
        // chosen_inline_result — «приглашение отправлено»; приходит лишь при
        // включённом отклике у BotFather, а без него просто не бывает
        allowed_updates: ['message', 'inline_query', 'chosen_inline_result']
      });
    } catch (ошибка) {
      if (ошибка.код === 409) {
        console.error('Похоже, этот же бот уже где-то запущен. Закройте вторую копию — двум сразу Telegram сообщения не отдаёт.');
      } else {
        console.error('Связь с Telegram прервалась (' + ошибка.message + '). Пробую снова через 5 секунд.');
      }
      await пауза(5000);
      continue;
    }

    for (const обновление of новости) {
      следующее = обновление.update_id + 1;
      try {
        await обработать(обновление, имяБота);
      } catch (ошибка) {
        // Одно неудачное сообщение не должно останавливать бота
        console.error('Не смог ответить на одно сообщение: ' + ошибка.message);
      }
    }
  }
}

process.on('SIGINT', function () {
  // Счёт сохраняется после каждого захода, но перед выходом сохраним ещё раз —
  // так надёжнее, а стоит это доли секунды
  try { СЧЁТЧИК.сохранить(); } catch (сбой) { /* остановке это помешать не должно */ }
  console.log('\nБот остановлен.');
  process.exit(0);
});

работать().catch(function (ошибка) {
  console.error('Бот остановился из-за ошибки: ' + ошибка.message);
  process.exit(1);
});
