/** Откуда пришёл человек — определяем по самому сообщению.
    В личной переписке смотрим на хвостик команды /start: если игрок пришёл
    по ссылке-приглашению вида t.me/бот?start=метка, Telegram кладёт метку
    сюда же, в текст. Пустой хвостик — значит открыл бота напрямую. */
function откудаПришёл(сообщение) {
  const чат = сообщение.chat || {};
  if (чат.type !== 'private') return Статистика.ИСТОЧНИКИ.группа;

  // Размеченная ссылка (?start=src_…) — это не друг позвал, а человек пришёл
  // из места, где мы рассказали об игре: каталог, статья, пост
  if (меткаИсточника(сообщение)) return Статистика.ИСТОЧНИКИ.ссылка;

  const текст = (сообщение.text || '').trim();
  const начало = /^\/start(@\S+)?(\s+(\S+))?$/.exec(текст);
  if (начало && начало[3]) return Статистика.ИСТОЧНИКИ.приглашение;

  return Статистика.ИСТОЧНИКИ.прямая;
}

/** Метка размеченной ссылки из хвоста команды «/start src_<метка>».
    Такие ссылки мы сами расставляем по местам, где рассказываем об игре
    (t.me/бот?start=src_habr), а кнопка «Добавить в свой чат» несёт
    метку group — её Telegram присылает уже в группу, строкой
    «/start@ИмяБота src_group». Метки нет или в ней недопустимые знаки —
    пустая строка. */
function меткаИсточника(сообщение) {
  const текст = (сообщение.text || '').trim();
  const разбор = /^\/start(@\S+)?\s+src_(\S+)$/.exec(текст);
  if (!разбор) return '';
  // Регистр выравниваем: ссылку перепечатывают руками, и «src_Habr» —
  // та же метка, что «src_habr», а не приглашение друга
  const метка = разбор[2].toLowerCase();
  return Статистика.МЕТКА_ССЫЛКИ.test(метка) ? метка : '';
}

