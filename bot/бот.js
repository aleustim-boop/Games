/** Это владелец бота? Сравниваем номер человека с тем, что записан в bot/.env.
    Номер не задан — значит владельца бот не знает и никого им не считает. */
function этоВладелец(сообщение) {
  if (!НАСТРОЙКИ.номерВладельца) return false;
  const кто = сообщение.from && сообщение.from.id;
  return String(кто) === НАСТРОЙКИ.номерВладельца;
}

/** Команда из сообщения: «/статистика@ИмяБота» → «/статистика». */
function командаИзСообщения(сообщение) {
  const текст = (сообщение.text || '').trim().toLowerCase();
  const первоеСлово = текст.split(/\s+/)[0] || '';
  return первоеСлово.split('@')[0];
}

/* Одну и ту же команду удобно набирать и по-русски, и латиницей:
   на телефоне переключать раскладку ради одного слова — лишняя морока. */
const КОМАНДЫ_СТАТИСТИКИ = ['/статистика', '/stats'];
const КОМАНДЫ_НОМЕРА = ['/мойномер', '/myid'];

/** Отвечает ли бот на это сообщение статистикой. Если да — отвечает и
    возвращает правду, чтобы приветствие уже не слать.

    Постороннему бот про статистику не говорит вовсе: он получит обычное
    приветствие, как будто написал что угодно другое. */
async function ответитьПроСтатистику(сообщение) {
  const команда = командаИзСообщения(сообщение);
  const чат = сообщение.chat || {};

  if (КОМАНДЫ_НОМЕРА.indexOf(команда) !== -1) {
    const кто = (сообщение.from && сообщение.from.id) || '?';
    await вызовAPI('sendMessage', {
      chat_id: чат.id,
      text: 'Ваш номер в Telegram: ' + кто + '\n\n' +
        'Если это вы — владелец игры, впишите в файл bot/.env строку\n' +
        'OWNER_ID=' + кто + '\n' +
        'и перезапустите бота. Тогда команда /статистика будет отвечать вам.'
    });
    return true;
  }

  if (КОМАНДЫ_СТАТИСТИКИ.indexOf(команда) === -1) return false;

  // Владелец не указан — объясняем, как указать, вместо молчания
  if (!НАСТРОЙКИ.номерВладельца) {
    await вызовAPI('sendMessage', {
      chat_id: чат.id,
      text: 'Статистику бот показывает только владельцу, а владелец пока не указан.\n\n' +
        'Что сделать: узнайте свой номер командой /мойномер, впишите в файл bot/.env строку ' +
        'OWNER_ID=<номер> и перезапустите бота.'
    });
    return true;
  }

  if (!этоВладелец(сообщение)) return false;

  // Отчёт — только в личку: в общем чате цифры увидели бы все участники
  if (чат.type !== 'private') {
    await вызовAPI('sendMessage', {
      chat_id: чат.id,
      text: 'Статистику показываю только в личной переписке — напишите мне эту команду там.'
    });
    return true;
  }

  /* Вторая половина отчёта — партии — живёт на сервере комнат. Его адрес
     бот берёт из того же хвостика «?сервер=», что и игра. Что передаём в отчёт:
     объект — цифры сервера; строка — почему их нет; пусто — адрес не задан. */
  const адресСервера = адресСервераИзАдресаИгры(НАСТРОЙКИ.адресИгры);
  let сервер = '';
  if (адресСервера) {
    сервер = (await спроситьСерверКомнат(адресСервера)) ||
      'Сервер комнат не отвечает — партии за сегодня неизвестны. Цифры бота выше — как есть.';
  }

  let текст;
  try {
    текст = Статистика.текстОтчёта(СЧЁТЧИК.цифры(), сервер);
  } catch (сбой) {
    текст = 'Не смог собрать статистику: ' + сбой.message;
  }

  await вызовAPI('sendMessage', { chat_id: чат.id, text: текст });
  return true;
}

/** Метка игры, допустимая для ссылки: только латиница, цифры, «_» и «-»,
    не длиннее 64 знаков — тот же предел, что у Telegram в хвосте ?start=.
    Всё прочее (кириллица, пробелы, слишком длинная строка) — не годится,
    в ответ и в ссылку такая метка попасть не должна. */
const МЕТКА_ИГРЫ_В_ССЫЛКЕ = /^[a-z0-9_-]{1,64}$/;

/** Метка игры из хвоста команды «/start invite_<метка>» — саму метку,
    если она нашлась и состоит из допустимых знаков. «/start invite» без
    метки, обычный «/start» и любой другой хвост дают пустую строку —
    тогда ответ остаётся прежним, общим приветствием. */
function меткаПриглашенияВИгру(сообщение) {
  const текст = (сообщение.text || '').trim();
  const разбор = /^\/start(@\S+)?\s+invite_(\S+)$/.exec(текст);
  if (!разбор) return '';
  const метка = разбор[2];
  return МЕТКА_ИГРЫ_В_ССЫЛКЕ.test(метка) ? метка : '';
}

/** Строка общей таблицы игр (server/названия.js) по метке из ссылки-
    приглашения. Метка не нашлась в таблице (опечатка, старая или чужая
    ссылка) — null, и приглашение уходит по общему пути. */
function игруПозвалиПоМетке(метка) {
  if (!метка) return null;
  for (const строка of Названия.ИГРЫ) {
    if (строка.метка === метка) return строка;
  }
  return null;
}

/** Человека позвали ссылкой-карточкой в конкретную игру (см. кнопку
    «Пригласить друзей» — js/похвастаться.js, ссылку собирает сервер —
    server/сервер.js). Если метка известна, отвечаем сразу про эту игру
    и возвращаем true — общее приветствие уже не шлём. Иначе ничего не
    делаем и возвращаем false: дальше ответит ответитьНаСообщение. */
async function ответитьНаПриглашениеВИгру(сообщение, имяБота) {
  const чат = сообщение.chat || {};
  if (чат.type !== 'private') return false;

  const играСтрока = игруПозвалиПоМетке(меткаПриглашенияВИгру(сообщение));
  if (!играСтрока) return false;

  await позватьВИгру(сообщение, имяБота, играСтрока);
  return true;
}

/** Сам ответ «Вас зовут сыграть в …» с кнопкой «Играть» в эту игру —
    один на обе ссылки-приглашения: старую invite_<метка> и новую
    inv_<код>_<метка>. */
async function позватьВИгру(сообщение, имяБота, играСтрока) {
  const чат = сообщение.chat || {};
  const имя = (сообщение.from && сообщение.from.first_name) || '';
  const текст = 'Привет' + (имя ? ', ' + имя : '') + '! 🎲\n\n' +
    'Вас зовут сыграть ' + играСтрока.вИгру + '. ' +
    'Жмите «Играть» — стол откроется прямо здесь, в Telegram.';
  const кнопки = { inline_keyboard: [[{ text: 'Играть', url: ссылкаНаИгру(имяБота, играСтрока.метка) }]] };

  await отправитьПриветствие(чат.id, текст, кнопки);
}

/* Хвост ссылки «Позвать друга»: inv_<код>[_<метка>]. Код — восемь знаков,
   по нему сервер узнаёт пригласившего; метка игры — как у invite_<метка>.
   Ту же ссылку собирает сервер (server/сервер.js) — вид хвоста один
   на двоих и меняется сразу в обоих местах. */
const ХВОСТ_ПОЗВАТЬ_ДРУГА = /^inv_([a-z0-9]{8})(?:_([a-z0-9-]+))?$/;

/** Код пригласившего и метка игры из команды «/start inv_<код>[_<метка>]» —
    { код, метка } (метка бывает пустой). Хвост другого вида, в том числе
    с мусорным кодом, — null: тогда серверу ничего не говорим. */
function ктоПозвалДруга(сообщение) {
  const текст = (сообщение.text || '').trim();
  const начало = /^\/start(@\S+)?\s+(\S+)$/.exec(текст);
  if (!начало) return null;
  const разбор = ХВОСТ_ПОЗВАТЬ_ДРУГА.exec(начало[2]);
  if (!разбор) return null;
  return { код: разбор[1], метка: разбор[2] || '' };
}

/** Человек пришёл по ссылке «Позвать друга» (карточка «Пригласить друзей»).
    Отвечаем ему как на приглашение в игру — про игру из метки или, если
    метки нет либо она незнакомая, общим приветствием, — а потом говорим
    серверу комнат, кто пришёл: он привяжет друга к пригласившему
    (POST /друг-пришёл, server/привёл-друга.js). Номер друга берём только
    из самого сообщения Telegram. Сервер молчит или отказал — человеку
    всё равно: его ответ уже ушёл. Возвращает true, если это была такая
    ссылка. */
async function ответитьПришедшемуПоЗову(сообщение, имяБота) {
  const чат = сообщение.chat || {};
  if (чат.type !== 'private') return false;

  const зов = ктоПозвалДруга(сообщение);
  if (!зов) return false;

  try {
    const играСтрока = игруПозвалиПоМетке(зов.метка);
    if (играСтрока) await позватьВИгру(сообщение, имяБота, играСтрока);
    else await ответитьНаСообщение(сообщение, имяБота);
  } finally {
    /* Приход случился, даже если ответ не ушёл (человек закрыл переписку).
       Сервер не ждём: он бывает выключен, и три секунды его молчания
       задерживали бы ответы всем, кто написал боту следом. */
    сказатьСерверуОДруге(сообщение, зов).catch(function () { /* учёт прихода — дело сервера */ });
  }
  return true;
}

/** Передаём серверу комнат, что по коду пригласившего пришёл человек.
    Тем же путём и пропуском, что отказы от писем. По ответу ничего
    не делаем: привязан друг или нет — решает и помнит сервер. Номер друга —
    только настоящий номер человека: бот, сообщение без отправителя
    или не число — серверу ничего не говорим. */
async function сказатьСерверуОДруге(сообщение, зов) {
  const от = сообщение.from || {};
  const друг = от.is_bot ? 0 : от.id;
  const адресСервера = адресСервераИзАдресаИгры(НАСТРОЙКИ.адресИгры);
  if (!Number.isSafeInteger(друг) || друг <= 0 || !адресСервера) return;

  await запросКСерверу(адресСервера, '/друг-пришёл',
    { пропускБота: ПРОПУСК_БОТА, код: зов.код, друг: друг, игра: зов.метка },
    СЕРВЕР_КОМНАТ_ОТВЕЧАЕТ_ЗА);
}

async function ответитьНаСообщение(сообщение, имяБота) {
  const чат = сообщение.chat || {};
  const личнаяПереписка = чат.type === 'private';
  const имя = (сообщение.from && сообщение.from.first_name) || '';

  if (личнаяПереписка) {
    await отправитьПриветствие(чат.id, приветствие(имя), кнопкиДляЛички(имяБота));
    return;
  }

  await вызовAPI('sendMessage', {
    chat_id: чат.id,
    text: 'Напишите /играть — соберу стол прямо здесь. ' +
      'А выбрать игру и сыграть одному можно в личной переписке со мной.',
    reply_markup: кнопкиДляГруппы(имяБота)
  });
}

/** В группе это сообщение не нам? Отвечаем там только на команды —
    и только на свои.

    Без этой проверки бот отвечал в группе на всё, что Telegram ему
    показывает: на служебные вести («в чат вошёл новый участник», «сменили
    название»), а при выключенной приватности — и на каждую реплику.
    Бот, который встревает в чужой разговор, из чата вылетает в тот же
    день. Команда с чужим именем («/play@ДругойБот») — тоже не наша.

    Команда без имени («/help», «/top») в группе с несколькими ботами
    приходит всем сразу, и чаще всего она чужая. Поэтому без имени
    откликаемся только на те команды, которые знаем сами; на незнакомую —
    лишь когда её прямо адресовали нам («/что@НашБот»). */
function неНамВГруппе(сообщение, имяБота) {
  const чат = сообщение.chat || {};
  if (чат.type === 'private') return false;

  const первоеСлово = (сообщение.text || '').trim().split(/\s+/)[0] || '';
  if (первоеСлово.charAt(0) !== '/') return true;

  const адресат = первоеСлово.split('@')[1] || '';
  if (адресат) return адресат.toLowerCase() !== String(имяБота || '').toLowerCase();

  return СВОИ_КОМАНДЫ_В_ГРУППЕ().indexOf(командаИзСообщения(сообщение)) === -1;
}

/** Команды, на которые бот в группе откликается и без «@имя». Функцией,
    а не списком: КОМАНДЫ_СТОЛА объявлены ниже по файлу. */
function СВОИ_КОМАНДЫ_В_ГРУППЕ() {
  return ['/start'].concat(КОМАНДЫ_СТОЛА, КОМАНДЫ_СТАТИСТИКИ, КОМАНДЫ_НОМЕРА);
}

/* Какие положения бота в чате значат «он там есть». */
const СТАТУСЫ_В_ЧАТЕ = ['member', 'administrator', 'creator'];

/** Бот в чате при таком положении? «restricted» — ограничен в правах,
    но в чате может и быть, и не быть: это говорит отдельный признак. */
function вЧате(участник) {
  const положение = участник || {};
  if (положение.status === 'restricted') return Boolean(положение.is_member);
  return СТАТУСЫ_В_ЧАТЕ.indexOf(положение.status) !== -1;
}

/* Сколько не здороваемся с одной группой повторно. О своём появлении
   в группе бот узнаёт дважды: вестью «вас добавили» (my_chat_member)
   и командой «/start@ИмяБота src_group», которую Telegram пишет в чат
   за человека, нажавшего «Добавить в свой чат». Два приветствия подряд —
   уже шум. */
const НЕ_ЗДОРОВАТЬСЯ_ПОВТОРНО = 2 * 60 * 1000;
const КОГДА_ЗДОРОВАЛИСЬ = new Map();   // номер чата → время последнего приветствия

/** Здороваемся с группой, куда бота только что добавили: одной репликой
    говорим, что он умеет и какой командой его позвать. Без этого бот
    молча висит в списке участников, и о нём забывают. */
async function поздороватьсяСГруппой(чатId, имяБота) {
  const сейчас = Date.now();
  if (сейчас - (КОГДА_ЗДОРОВАЛИСЬ.get(чатId) || 0) < НЕ_ЗДОРОВАТЬСЯ_ПОВТОРНО) return;
  КОГДА_ЗДОРОВАЛИСЬ.set(чатId, сейчас);
  // Память бота не бесконечна: о давних приветствиях помнить незачем
  for (const [чат, когда] of КОГДА_ЗДОРОВАЛИСЬ) {
    if (сейчас - когда >= НЕ_ЗДОРОВАТЬСЯ_ПОВТОРНО) КОГДА_ЗДОРОВАЛИСЬ.delete(чат);
  }

  await вызовAPI('sendMessage', {
    chat_id: чатId,
    text: 'Всем привет! 🎲 Я собираю стол для игры прямо в этом чате.\n\n' +
      'Напишите /играть или /play — спрошу, во что играем, и открою стол: ' +
      'сесть можно в одно касание, ставить ничего не надо.\n\n' +
      'А по кнопке ниже — весь сборник: ' + перечислитьЗапятыми(ИМЕНА_ИГР) + '.',
    reply_markup: кнопкиДляГруппы(имяБота)
  });
}

/** В группу пришла команда «/start@ИмяБота src_…» — её пишет сам Telegram,
    когда бота добавили кнопкой «Добавить в свой чат». Здороваемся
    и возвращаем true; на любое другое сообщение — false. */
async function ответитьНаДобавлениеВГруппу(сообщение, имяБота) {
  const чат = сообщение.chat || {};
  if (чат.type === 'private' || !меткаИсточника(сообщение)) return false;
  await поздороватьсяСГруппой(чат.id, имяБота);
  return true;
}

/** Telegram сообщил, что положение бота в чате изменилось: добавили,
    убрали, сделали администратором. Нас занимают только группы и только
    сам вход и выход — их считаем, а при входе здороваемся. */
async function принятьПеременуВЧате(перемена, имяБота) {
  const чат = перемена.chat || {};
  if (чат.type !== 'group' && чат.type !== 'supergroup') return;

  const был = вЧате(перемена.old_chat_member);
  const стал = вЧате(перемена.new_chat_member);
  if (был === стал) return;   // сменили права, а не вход и не выход

  отметитьГруппу(чат.id, стал);
  if (стал) await поздороватьсяСГруппой(чат.id, имяБота);
}

/** Человек набрал «@ИмяБота …» в поле ввода — отдаём Telegram готовое
    приглашение (тот же текст, что и у кнопки «Поделиться приложением»). */
async function ответитьНаПриглашение(запрос, имяБота) {
  await вызовAPI('answerInlineQuery', {
    inline_query_id: запрос.id,
    cache_time: 60,
    results: [{
      type: 'article',
      id: 'приглашение-в-игру',
      title: 'Позвать играть',
      description: 'Друг откроет сборник: ' + перечислитьЗапятыми(ИМЕНА_ИГР),
      input_message_content: {
        message_text: ТЕКСТ_ПРИГЛАШЕНИЯ
      },
      /* Ссылка ведёт прямо в игру. Особая кнопка «web_app» в чужом чате
         и правда не работает — Telegram разрешает её только в личной
         переписке с ботом, — но обычная ссылка на мини-приложение открывает
         игру откуда угодно. Именно она здесь и стоит. */
      reply_markup: {
        inline_keyboard: [[{ text: 'Открыть игры', url: ссылкаНаИгру(имяБота) }]]
      }
    }]
  });
}

async function обработать(обновление, имяБота) {
  if (обновление.message && обновление.message.chat) {
    const сообщение = обновление.message;

    // Чужой разговор в группе: не считаем и не отвечаем
    if (неНамВГруппе(сообщение, имяБота)) return;

    // Считаем человека до ответа: даже если ответ не уйдёт (человек закрыл
    // переписку с ботом), приход уже случился и в счёте должен остаться
    if (сообщение.from && сообщение.from.id && !сообщение.from.is_bot) {
      отметитьЗаход(сообщение.from.id, откудаПришёл(сообщение), меткаИсточника(сообщение));
    }

    if (await ответитьНаДобавлениеВГруппу(сообщение, имяБота)) return;

    // Стол из чата: на команду игры бот создаёт стол и кладёт в чат кнопку,
    // на /играть без названия — сначала спрашивает, во что играем
    const команда = командаИзСообщения(сообщение);
    if (КОМАНДЫ_СТОЛА.indexOf(команда) !== -1) {
      await ответитьНаКомандуСтола(сообщение, команда, имяБота);
      return;
    }

    if (await ответитьПришедшемуПоЗову(сообщение, имяБота)) return;
    if (await ответитьНаПриглашениеВИгру(сообщение, имяБота)) return;
    if (await ответитьПроСтатистику(сообщение)) return;
    await ответитьНаСообщение(сообщение, имяБота);
    return;
  }
  if (обновление.callback_query) {
    const нажатие = обновление.callback_query;
    if (нажатие.data === ОТКАЗ_ОТ_ЗОВОВ) {
      await принятьОтказОтЗовов(нажатие);
      return;
    }
    if (нажатие.data === ОТКАЗ_ОТ_ИТОГОВ) {
      await принятьОтказОтИтогов(нажатие);
      return;
    }
    if (нажатие.data === ОТКАЗ_ОТ_ВОЗВРАТА) {
      await принятьОтказОтВозврата(нажатие);
      return;
    }
    if (typeof нажатие.data === 'string' && нажатие.data.indexOf(КНОПКА_СТОЛА) === 0) {
      await принятьВыборИгры(нажатие, имяБота);
      return;
    }
    /* Незнакомая кнопка (старое письмо, чужая затея). Молчать нельзя:
       Telegram крутит человеку часики, пока бот не ответит хоть что-то. */
    await вызовAPI('answerCallbackQuery', { callback_query_id: нажатие.id });
    return;
  }
  if (обновление.inline_query) {
    // Человек набрал «@ИмяБота …» — Telegram сообщает об этом самому боту,
    // чужих переписок для этого читать не нужно
    отметитьПриглашение(обновление.inline_query.from, false);
    await ответитьНаПриглашение(обновление.inline_query, имяБота);
    return;
  }
  if (обновление.chosen_inline_result) {
    // Приглашение и правда ушло в чат. Такие вести Telegram шлёт, только если
    // у BotFather включён отклик (/setinlinefeedback); отвечать на них не надо
    отметитьПриглашение(обновление.chosen_inline_result.from, true);
    return;
  }
  if (обновление.my_chat_member) {
    await принятьПеременуВЧате(обновление.my_chat_member, имяБота);
  }
}

/* Команды «сыграть во что-нибудь»: без названия игры бот спросит, во что.
   Латинский двойник нужен для подсказки команд — в неё Telegram берёт
   только латиницу (см. КОМАНДЫ_ДЛЯ_ГРУПП) — и для групп: там до бота
   русская команда может и не дойти. */
const КОМАНДЫ_ВЫБОРА = ['/играть', '/play'];

/* Команды игр: по ним стол открывается сразу, без вопроса. У каждой игры
   из таблицы названий их две — латинская метка (/shahmaty) и русское
   слово (/шахматы, /морской_бой: дефиса в команде Telegram не бывает).
   Новая игра в таблице получает свои команды сама. */
const ИГРА_ПО_КОМАНДЕ = Object.create(null);
Названия.сетевыеИгры().forEach(function (игра) {
  ИГРА_ПО_КОМАНДЕ['/' + Названия.меткаИгры(игра)] = игра;
  ИГРА_ПО_КОМАНДЕ['/' + игра.replace(/-/g, '_')] = игра;
});

/* Все команды, по которым бот занимается столом. */
const КОМАНДЫ_СТОЛА = КОМАНДЫ_ВЫБОРА.concat(Object.keys(ИГРА_ПО_КОМАНДЕ));

/* С этого начинается callback_data кнопки «открыть стол такой-то игры»:
   «stol:shahmaty». Такие кнопки стоят в меню выбора игры и под итогом
   партии в группе («Реванш?» — его шлёт сервер, а нажатие приходит боту). */
const КНОПКА_СТОЛА = 'stol:';

const ВОПРОС_ОБ_ИГРЕ = 'Во что играем?';

/** Как человек может назвать игру словом после команды: «шахматы»,
    «в монополию», «морской бой», «shashki». Пробелы, дефисы и подчёркивания
    равны, регистр не важен. */
function приметаИгры(слова) {
  return String(слова || '').toLowerCase().replace(/ё/g, 'е')
    .replace(/[\s_-]+/g, ' ').trim().replace(/^(в|во) /, '');
}

/** Игра из слов после команды: «/играть в нарды» → «нарды». Слов нет или
    игра незнакома — пустая строка: тогда бот спросит кнопками. */
function играИзСлов(текст) {
  const послеКоманды = String(текст || '').trim().split(/\s+/).slice(1).join(' ');
  const примета = приметаИгры(послеКоманды);
  if (!примета) return '';
  for (const строка of Названия.ИГРЫ) {
    if (!строка.метка) continue;
    const имена = [строка.игра, строка.метка, строка.название, строка.заСтолом, строка.партия];
    for (const имя of имена) {
      if (приметаИгры(имя) === примета) return строка.игра;
    }
  }
  return '';
}

/** Кнопки выбора игры — по две в ряд, в порядке таблицы названий. */
function кнопкиВыбораИгры() {
  const ряды = [];
  Названия.сетевыеИгры().forEach(function (игра, номер) {
    const слова = Названия.словаИгры(игра);
    if (номер % 2 === 0) ряды.push([]);
    ряды[ряды.length - 1].push({ text: слова.название, callback_data: КНОПКА_СТОЛА + слова.метка });
  });
  return { inline_keyboard: ряды };
}

/** Пришла команда стола. Игра названа (командой или словом) — открываем
    стол сразу; не названа — спрашиваем кнопками. */
async function ответитьНаКомандуСтола(сообщение, команда, имяБота) {
  const игра = ИГРА_ПО_КОМАНДЕ[команда] || играИзСлов(сообщение.text);
  if (игра) {
    await столИзЧата(имяБота).позватьКСтолу(сообщение, игра);
    return;
  }
  await вызовAPI('sendMessage', {
    chat_id: сообщение.chat.id,
    text: ВОПРОС_ОБ_ИГРЕ,
    reply_markup: кнопкиВыбораИгры()
  });
}

/** Человек нажал кнопку игры. Открываем стол от его имени. На само
    нажатие отвечает стол из чата (иначе Telegram крутит человеку часики):
    он же знает, открыт стол или отказ, — отказ покажет всплывающим окном.

    Если кнопка стояла в нашем меню «Во что играем?» — меню превращается
    в приглашение: второй раз нажать нечего. Если кнопка была под чужим
    текстом (итог партии с «Реванш?») — тот текст не трогаем, приглашение
    идёт новым сообщением. */
async function принятьВыборИгры(нажатие, имяБота) {
  const игра = Названия.играПоМетке(нажатие.data.slice(КНОПКА_СТОЛА.length));
  const где = нажатие.message;
  // Незнакомая метка или сообщение, которого бот уже не видит, — стола не будет
  if (!игра || !где || !где.chat) {
    try {
      await вызовAPI('answerCallbackQuery', { callback_query_id: нажатие.id });
    } catch (сбой) {
      /* нажатие устарело — отвечать уже некому */
    }
    return;
  }

  const этоМеню = где.text === ВОПРОС_ОБ_ИГРЕ;
  await столИзЧата(имяБота).позватьКСтолу(
    { chat: где.chat, from: нажатие.from },
    игра,
    этоМеню ? где.message_id : undefined,
    нажатие.id
  );
}

/* Стол из чата собирается один раз, при первой команде: ему нужно имя бота,
   а оно известно только после запуска. Всё, что ходит наружу, отдаём ему
   готовыми функциями — модуль сам ни про Telegram, ни про сеть не знает. */
let СТОЛ_ИЗ_ЧАТА = null;
function столИзЧата(имяБота) {
  if (!СТОЛ_ИЗ_ЧАТА) {
    СТОЛ_ИЗ_ЧАТА = СтолИзЧата.создать({
      вызовAPI: вызовAPI,
      запросКСерверу: запросКСерверу,
      адресСервера: function () { return адресСервераИзАдресаИгры(НАСТРОЙКИ.адресИгры); },
      имяБота: function () { return имяБота; },
      короткоеИмя: КОРОТКОЕ_ИМЯ_ИГРЫ,
      пропускБота: ПРОПУСК_БОТА,
      названия: Названия,
      отметитьВызов: отметитьВызов
    });
  }
  return СТОЛ_ИЗ_ЧАТА;
}

/** Отмечаем в счёте стол, открытый командой /играть. Беда с файлом бота не роняет. */
