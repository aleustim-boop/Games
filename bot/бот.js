/* НАЧАЛО-ТЕКСТЫ-ИГР — маркер для tests/поделиться-приложением.js: он
   вырезает этот кусок и проверяет тексты без запуска бота целиком (боту
   для старта нужен настоящий bot/.env, а этим строкам — только таблица
   server/названия.js). Маркер не переносить и не переименовывать. */

/** Список слов через запятую с «и» перед последним: «дурак, шашки и нарды».
    Список игр в текстах бота собирается из одной таблицы, а не пишется
    руками, — появится новая игра, и здесь она встанет сама. */
function перечислитьЗапятыми(слова) {
  if (слова.length <= 1) return слова.join('');
  return слова.slice(0, -1).join(', ') + ' и ' + слова[слова.length - 1];
}

/* Имена всех игр сборника, как их показывает кнопка «Сесть за стол: …» —
   с заглавной буквы (server/названия.js, поле «название»). */
const ИМЕНА_ИГР = Названия.ИГРЫ.map(function (строка) { return строка.название; });

/* Приглашение, которое человек отправляет другу.

   Зовём в сборник, а не в отдельную игру: мы не знаем, во что другу захочется
   играть. Называть игру по имени можно только там, где это правда, — например,
   в сообщении про уже созданный стол.

   Про код комнаты здесь больше ни слова: игра сама ведёт за стол по ссылке,
   а объяснение того, чего человек ещё не видел, только удлиняет текст. */
const ТЕКСТ_ПРИГЛАШЕНИЯ =
  'Играем? Тут сборник настольных игр прямо в Telegram: ' + перечислитьЗапятыми(ИМЕНА_ИГР) + '.\n' +
  'Ставить ничего не надо — открывай и выбирай.\n' +
  'Можно с ботом, а можно вдвоём — живьём друг против друга.';

/** Строка про одну игру для приветствия: «• Название — способ игры».
    Игры со своей меткой ссылки играются и с ботом, и по сети вдвоём;
    без метки (сейчас — только шахматы) сеть пока не разобрана, только бот. */
function строкаИгрыДляПриветствия(строка) {
  const способ = строка.метка ? 'с ботом или вдвоём с живым другом' : 'с ботом';
  return '• ' + строка.название + ' — ' + способ;
}

/* Приветствие короткое нарочно. Первый экран человек читает три секунды,
   и всё, что не поместилось, он не читает вовсе. Поэтому здесь только то,
   чего он сам не угадает: какие есть игры, что можно звать живого друга
   и что в общем чате работает /играть. Коды столов и то, как устроена
   кнопка «Поделиться приложением», написаны на самих экранах игры —
   повторять их здесь незачем. */
function приветствие(имя) {
  const списокИгр = Названия.ИГРЫ.map(строкаИгрыДляПриветствия).join('\n');
  return 'Привет' + (имя ? ', ' + имя : '') + '! 🎲\n\n' +
    'Уже ' + Названия.ИГРЫ.length + ' настольных игр прямо в Telegram, ставить ничего не надо:\n' +
    списокИгр + '\n\n' +
    'Жмите «Играть» и выбирайте, во что.\n' +
    'А в общем чате напишите /играть — соберу стол прямо там.';
}

/* КОНЕЦ-ТЕКСТЫ-ИГР */

/* Сколько знаков Telegram разрешает в подписи к картинке. Само приветствие
   гораздо короче, но проверить дешевле, чем однажды получить отказ и остаться
   вовсе без ответа. */
const ДЛИНА_ПОДПИСИ = 1024;

/** Приветствие с обложкой, если обложка задана и всё прошло гладко.

    Картинки в проекте нет — это правило, а не забывчивость. Поэтому здесь
    заложена только дорога для неё: появится в настройках строка
    WELCOME_PHOTO с обычной ссылкой на картинку (её раздаст сайт игры) —
    бот пошлёт картинку с подписью и теми же кнопками одним сообщением.
    Нет строки, картинка не открылась, подпись не влезла — человек получает
    ровно то же приветствие обычным текстом, как раньше. */
async function отправитьПриветствие(чатId, текст, кнопки) {
  const обложка = НАСТРОЙКИ.обложка;

  if (обложка && текст.length <= ДЛИНА_ПОДПИСИ) {
    try {
      await вызовAPI('sendPhoto', {
        chat_id: чатId,
        photo: обложка,
        caption: текст,
        reply_markup: кнопки
      });
      return;
    } catch (сбой) {
      // Телеграм не взял картинку (нет по ссылке, слишком большая) —
      // человек не должен остаться без ответа из-за оформления
      console.error('Не смог отправить обложку, шлю приветствие текстом: ' + сбой.message);
    }
  }

  await вызовAPI('sendMessage', { chat_id: чатId, text: текст, reply_markup: кнопки });
}

/** Ссылка «поделиться»: Telegram показывает выбор чата и кладёт туда готовое
    приглашение вместе со ссылкой на игру.

    Раньше на этом месте стояла кнопка особого вида (switch_inline_query).
    Она устроена иначе: Telegram подставляет человеку в поле ввода строку
    «@ИмяБота Сыграем…» — техническую, нужную боту для поиска, — и владелец
    справедливо спросил, что это за надпись. Убрать оттуда имя бота нельзя,
    так работает сам режим. У обычной ссылки «поделиться» этого нет вовсе:
    человек выбирает чат и сразу отправляет готовый текст. Тем же способом
    приглашает и сама игра (см. js/сеть.js). */
function ссылкаПоделиться(имяБота) {
  return 'https://t.me/share/url?url=' + encodeURIComponent(ссылкаНаИгру(имяБота)) +
    '&text=' + encodeURIComponent(ТЕКСТ_ПРИГЛАШЕНИЯ);
}

/* Метка, с которой бот приезжает в группу по кнопке «Добавить в свой чат».
   По ней в статистике видно, что группу привела именно эта кнопка. */
const МЕТКА_КНОПКИ_В_ЧАТ = 'group';

/** Ссылка «добавить бота в чат»: Telegram показывает человеку список его
    групп, а после выбора сам пишет в группу «/start@ИмяБота src_group».
    Это единственный честный способ попасть в чужой чат — туда бота
    приводит его же участник, а не мы. */
function ссылкаДобавитьВЧат(имяБота) {
  return 'https://t.me/' + имяБота + '?startgroup=src_' + МЕТКА_КНОПКИ_В_ЧАТ;
}

/** Кнопки для личного чата: «Играть» открывает игру прямо в Telegram. */
function кнопкиДляЛички(имяБота) {
  return {
    inline_keyboard: [
      [{ text: 'Играть', web_app: { url: НАСТРОЙКИ.адресИгры } }],
      [{ text: 'Поделиться приложением', url: ссылкаПоделиться(имяБота) }],
      [{ text: 'Добавить в свой чат', url: ссылкаДобавитьВЧат(имяБота) }]
    ]
  };
}

/** Ставим постоянную кнопку «Играть» слева от поля ввода (кнопка меню Telegram).
    Кнопка в сообщении хороша один раз: стоит пролистать переписку — и её надо
    искать. Кнопка меню видна всегда.

    Ставится один раз при запуске и запоминается на стороне Telegram —
    для всех личных чатов с ботом сразу.

    Возвращаем пустую строку, если получилось, и объяснение — если Telegram
    отказал. Отказ бота не роняет: без этой кнопки всё живёт, игра открывается
    кнопкой из ответа на /start. */
async function поставитьКнопкуМеню() {
  try {
    await вызовAPI('setChatMenuButton', {
      menu_button: {
        type: 'web_app',
        text: 'Играть',
        web_app: { url: НАСТРОЙКИ.адресИгры }
      }
    });
    return '';
  } catch (ошибка) {
    return ошибка.message;
  }
}

/* Команды, которые Telegram подсказывает человеку, стоит набрать «/».
   В списке могут быть только латинские имена — так устроен сам Telegram,
   поэтому «/играть» в подсказку не поставить, и рядом с ним живёт «/play».
   Команды владельца (/статистика, /мойномер) сюда не идут: посторонним
   их видеть незачем. */
/* Команды игр для подсказки: имя команды — метка игры из таблицы названий
   (/shahmaty, /nardy…), подпись — «Стол в шахматы». */
const КОМАНДЫ_ИГР = Названия.сетевыеИгры().map(function (игра) {
  const слова = Названия.словаИгры(игра);
  return { command: слова.метка, description: 'Стол ' + слова.вИгру };
});
const КОМАНДЫ_ДЛЯ_ЛИЧКИ = [
  { command: 'start', description: 'Открыть игры' },
  { command: 'play', description: 'Позвать друзей за стол — выбрать игру' }
].concat(КОМАНДЫ_ИГР);
const КОМАНДЫ_ДЛЯ_ГРУПП = [
  { command: 'play', description: 'Собрать стол прямо в чате — выбрать игру' }
].concat(КОМАНДЫ_ИГР);

/* Короткая строка под именем бота в его карточке и в поиске Telegram
   (не длиннее 120 знаков). */
const КОРОТКОЕ_ОПИСАНИЕ_БОТА = 'Настольные и карточные игры прямо в Telegram — ' +
  'с ботом или с живыми друзьями. Ставить ничего не надо.';

/* Предел Telegram для текста на пустом экране бота («Что умеет этот бот?»). */
const ДЛИНА_ОПИСАНИЯ_БОТА = 512;

/** Текст, который человек видит ДО того, как нажал «старт». Это первое,
    что читает пришедший из поиска или по ссылке, — пустой экран здесь
    значит, что он уйдёт, так и не узнав, что внутри. */
function описаниеБота() {
  const начало = 'Настольные и карточные игры прямо в Telegram';
  const конец = '.\n\nИграйте с ботом или с живыми друзьями — ставить ничего не надо.\n\n' +
    'Добавьте меня в свой чат и напишите /play — соберу стол прямо там.';
  const сИграми = начало + ': ' + перечислитьЗапятыми(ИМЕНА_ИГР) + конец;
  // Игр станет больше — список перестанет влезать; тогда лучше без списка,
  // чем отказ Telegram и пустой экран
  return сИграми.length <= ДЛИНА_ОПИСАНИЯ_БОТА ? сИграми : начало + конец;
}

/** Оформляем карточку бота: описание, короткая строка и подсказки команд.
    Как и кнопка меню, ставится при запуске и запоминается на стороне
    Telegram. Возвращаем список отказов (пустой — всё встало). Отказ бота
    не роняет: это оформление, игра работает и без него. */
async function оформитьКарточкуБота() {
  const шаги = [
    ['setMyDescription', { description: описаниеБота() }],
    ['setMyShortDescription', { short_description: КОРОТКОЕ_ОПИСАНИЕ_БОТА }],
    ['setMyCommands', { commands: КОМАНДЫ_ДЛЯ_ЛИЧКИ, scope: { type: 'all_private_chats' } }],
    ['setMyCommands', { commands: КОМАНДЫ_ДЛЯ_ГРУПП, scope: { type: 'all_group_chats' } }]
  ];
  const отказы = [];
  for (const шаг of шаги) {
    try {
      await вызовAPI(шаг[0], шаг[1]);
    } catch (ошибка) {
      отказы.push(шаг[0] + ': ' + ошибка.message);
    }
  }
  return отказы;
}

/* Короткое имя мини-приложения у бота. Из него собирается прямая ссылка
   вида https://t.me/ИМЯ_БОТА/BoardGames — она открывает саму игру, а не
   переписку с ботом. Имя задаётся в настройках бота у BotFather; поменяете
   там — поменяйте и здесь. */
const КОРОТКОЕ_ИМЯ_ИГРЫ = 'BoardGames';

/* Хвостик «startapp» для ссылки на мини-приложение.

   Зачем он нужен. Ссылка вида t.me/БОТ/BoardGames открывает игру внутри
   Telegram, но по адресу, записанному у BotFather, — а он про наш домашний
   сервер комнат ничего не знает. Игра, открытая так, адреса сервера не видит
   вовсе и честно говорит «играть с другом сейчас не получится». Поэтому
   адрес мы кладём прямо в ссылку.

   Форма общая с игрой: <метка игры>_<код стола>-<адрес сервера буквами>,
   и любая часть может быть пустой. Здесь стола нет, поэтому код пустой —
   получается «-<адрес>», а с меткой «shashki_-<адрес>». Разбирает это
   js/сеть.js; адрес едет в base64url, потому что startapp принимает только
   латиницу, цифры, «_» и «-» и не длиннее 512 знаков.

   Адреса в настройках нет — адрес в хвостик не идёт, но метка игры всё
   равно нужна: js/сеть.js умеет открыть игру по одной метке без адреса
   (отделитьМеткуИгры), и без неё кнопка «Играть» в приглашении открывала
   бы не ту игру, о которой говорит текст. */
function хвостикСАдресом(меткаИгры) {
  const адресСервера = адресСервераИзАдресаИгры(НАСТРОЙКИ.адресИгры);
  if (!адресСервера) return меткаИгры || '';

  const хвостик = (меткаИгры ? меткаИгры + '_' : '') + '-' +
    СтолИзЧата.буквамиИзАдреса(адресСервера);
  // Слишком длинный Telegram просто не примет — лучше ссылка без адреса
  return хвостик.length <= 512 ? хвостик : '';
}

/** Прямая ссылка на игру. Метка игры необязательна: без неё откроется
    та игра, на которую ведёт само мини-приложение. */
function ссылкаНаИгру(имяБота, меткаИгры) {
  const хвостик = хвостикСАдресом(меткаИгры);
  return 'https://t.me/' + имяБота + '/' + КОРОТКОЕ_ИМЯ_ИГРЫ +
    (хвостик ? '?startapp=' + хвостик : '');
}

/** Кнопки для группы: ведут прямо в игру.

    Раньше здесь стояла ссылка на самого бота — с доводом, что кнопку «открыть
    игру» Telegram разрешает только в личной переписке. Довод верен ровно
    наполовину: КНОПКА особого вида (web_app) в чужом чате и правда
    не сработает, а обычная ссылка на мини-приложение работает везде.
    Из-за прежней осторожности человек попадал не в игру, а в переписку
    с ботом — и должен был там ещё что-то нажать. Лишний шаг на самом входе
    стоит дороже всего: до игры доходили не все. */
function кнопкиДляГруппы(имяБота) {
  return {
    inline_keyboard: [
      [{ text: 'Открыть игры', url: ссылкаНаИгру(имяБота) }]
    ]
  };
}

