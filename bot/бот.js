/* Сколько знаков Telegram разрешает в подписи к картинке. Само приветствие
   гораздо короче, но проверить дешевле, чем однажды получить отказ и остаться
   вовсе без ответа. */
const ДЛИНА_ПОДПИСИ = 1024;

/** Приветствие с обложкой, если обложка задана и всё прошло гладко.

    Картинки в проекте нет — это правило, а не забывчивость. Поэтому здесь
    заложена только дорога для неё: появится в настройках строка
    WELCOME_PHOTO с обычной ссылкой на картинку (её раздаст сайт игры) —
    бот пошлёт картинку с подписью и теми же кнопками одним сообщением.
    Нет строки, картинка не открылась, подпись не влезла — человек получает
    ровно то же приветствие обычным текстом, как раньше. */
async function отправитьПриветствие(чатId, текст, кнопки) {
  const обложка = НАСТРОЙКИ.обложка;

  if (обложка && текст.length <= ДЛИНА_ПОДПИСИ) {
    try {
      await вызовAPI('sendPhoto', {
        chat_id: чатId,
        photo: обложка,
        caption: текст,
        reply_markup: кнопки
      });
      return;
    } catch (сбой) {
      // Телеграм не взял картинку (нет по ссылке, слишком большая) —
      // человек не должен остаться без ответа из-за оформления
      console.error('Не смог отправить обложку, шлю приветствие текстом: ' + сбой.message);
    }
  }

  await вызовAPI('sendMessage', { chat_id: чатId, text: текст, reply_markup: кнопки });
}

