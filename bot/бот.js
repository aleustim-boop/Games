/** Отправляем Telegram один запрос и ждём ответ. Возвращает обещание (Promise). */
function вызовAPI(метод, данные) {
  return new Promise(function (успех, отказ) {
    const тело = Buffer.from(JSON.stringify(данные || {}), 'utf8');

    const запрос = https.request({
      hostname: 'api.telegram.org',
      path: '/bot' + НАСТРОЙКИ.токен + '/' + метод,
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Content-Length': тело.length
      },
      // Ждём дольше, чем длится ожидание новостей (getUpdates), иначе оборвём сами себя
      timeout: 65000
    }, function (ответ) {
      let текст = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        let разобрано;
        try {
          разобрано = JSON.parse(текст);
        } catch (ошибка) {
          отказ(new Error('Telegram ответил непонятным текстом'));
          return;
        }
        if (разобрано.ok) {
          успех(разобрано.result);
          return;
        }
        const сбой = new Error(разобрано.description || 'Telegram отказал');
        сбой.код = разобрано.error_code;
        отказ(сбой);
      });
    });

    запрос.on('timeout', function () { запрос.destroy(new Error('Telegram не ответил вовремя')); });
    запрос.on('error', отказ);
    запрос.end(тело);
  });
}

function пауза(миллисекунды) {
  return new Promise(function (готово) { setTimeout(готово, миллисекунды); });
}

/* Сколько ждём сервер комнат. Это домашний компьютер, он бывает выключен —
   владелец не должен ждать отчёт дольше трёх секунд. */
const СЕРВЕР_КОМНАТ_ОТВЕЧАЕТ_ЗА = 3000;

/** Один запрос к серверу комнат. Тело есть — POST с JSON, тела нет — GET.
    Возвращает { ок, номер, данные } — «ок» значит «ответ 2xx и в нём JSON», —
    а если сервер молчит, оборвал связь или адрес не разобрать, — null.
    Сервер отвечает JSON и на отказ (например, { ошибка: 'почему' }),
    поэтому «данные» есть и при ок = false. */
function запросКСерверу(адресСервера, путь, тело, ждать) {
  return new Promise(function (готово) {
    let адрес;
    try {
      // Хвостовой «/» убираем, как делает игра, иначе получится «//статистика»
      адрес = new URL(String(адресСервера || '').replace(/\/+$/, '') + путь);
    } catch (сбой) {
      готово(null);
      return;
    }

    let ответили = false;
    function отдать(что) {
      if (ответили) return;
      ответили = true;
      готово(что);
    }

    const телоЗапроса = тело === undefined ? null : Buffer.from(JSON.stringify(тело), 'utf8');
    // Тот же пропуск, что шлёт игра: туннель до домашнего сервера иначе
    // подсовывает страницу-напоминание вместо ответа
    const заголовки = { 'bypass-tunnel-reminder': 'true' };
    if (телоЗапроса) {
      заголовки['Content-Type'] = 'application/json';
      заголовки['Content-Length'] = телоЗапроса.length;
    }

    const модуль = адрес.protocol === 'http:' ? http : https;
    const запрос = модуль.request({
      hostname: адрес.hostname,
      port: адрес.port || undefined,
      // URL уже перевёл русское слово в проценты — сервер их разберёт обратно
      path: адрес.pathname + адрес.search,
      method: телоЗапроса ? 'POST' : 'GET',
      headers: заголовки,
      timeout: ждать || СЕРВЕР_КОМНАТ_ОТВЕЧАЕТ_ЗА
    }, function (ответ) {
      let текст = '';
      ответ.setEncoding('utf8');
      ответ.on('data', function (кусок) { текст += кусок; });
      ответ.on('end', function () {
        let данные = null;
        try { данные = JSON.parse(текст); } catch (сбой) { данные = null; }
        const номер = Number(ответ.statusCode) || 0;
        отдать({
          ок: номер >= 200 && номер < 300 && данные !== null,
          номер: номер,
          данные: данные
        });
      });
      ответ.on('error', function () { отдать(null); });
    });

    запрос.on('timeout', function () { запрос.destroy(new Error('сервер комнат не ответил вовремя')); });
    запрос.on('error', function () { отдать(null); });
    запрос.end(телоЗапроса || undefined);
  });
}

/** Спрашиваем у сервера комнат его счётчики партий: GET /статистика.
    Возвращаем разобранный ответ, а если сервер молчит или отвечает не тем —
    null. Ничего из ответа не храним: сервер сам помнит свои 60 дней,
    второй экземпляр тех же чисел только разъезжался бы. */
async function спроситьСерверКомнат(адресСервера) {
  const ответ = await запросКСерверу(адресСервера, '/статистика', undefined, СЕРВЕР_КОМНАТ_ОТВЕЧАЕТ_ЗА);
  if (!ответ || !ответ.ок) return null;
  const данные = ответ.данные;
  // Ответ похож на статистику, только если в нём все три окна
  const похоже = typeof данные === 'object' &&
    Boolean(данные.сегодня) && Boolean(данные.дней7) && Boolean(данные.дней30);
  return похоже ? данные : null;
}

