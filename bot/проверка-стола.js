  м.сервер.поведение.селНаОпросе = 1;
  await м.стол.позватьКСтолу(команда(613, 'Лена'), 'домино', 81, 'нажатие-4');
  проверить('стол не открылся (сервер лежал) — меню не занято, следующий стол его правит',
    м.телеграм.все('editMessageText').map(function (о) { return о.данные.message_id; }), [81]);
  await дождатьсяСторожей(м.стол);

  console.log('');
  console.log('9. Отказ по кнопке — всплывающим окном, а не сообщением в чат');

  м = собрать();
  м.сервер.поведение.ещёСекунд = СРОК_СЕРВЕРА;
  await м.стол.позватьКСтолу(команда(620, 'Дима'), 'шашки', undefined, 'нажатие-5');
