  проверить('закрылись оба — каждый сторож правит своё сообщение, а не чужое',
    м.телеграм.все('editMessageText').slice(1).map(function (о) {
      return [о.данные.message_id, о.данные.text.indexOf('Стол закрылся') === 0];
    }).sort(function (а, б) { return а[0] - б[0]; }),
    [[80, true], [101, true]]);
  проверить('второе приглашение было сообщением 101',
    !!второеПриглашение && м.телеграм.все('sendMessage').length, 1);

  м = собрать();
  м.сервер.поведение.лежит = true;
  await м.стол.позватьКСтолу(команда(612, 'Катя'), 'домино', 81, 'нажатие-3');
