  м.телеграм.поведение.нажатиеУстарело = true;
  проверить('нажатие устарело (Telegram ругается на ответ) — стол всё равно открыт',
    [await м.стол.позватьКСтолу(команда(621, 'Дима'), 'нарды', undefined, 'нажатие-7'),
     м.телеграм.все('sendMessage').length], [true, 1]);
  await дождатьсяСторожей(м.стол);

  console.log('');
  console.log('10. Потолки: столов на чат и столов всего');

  м = собрать();
  м.сервер.поведение.ещёСекунд = СРОК_СЕРВЕРА;
  for (let номер = 0; номер < СтолИзЧата.ПОТОЛОК_В_ЧАТЕ; номер++) {
    await м.стол.позватьКСтолу(команда(630 + номер, 'Гость'), 'домино');
  }
  проверить('потолок на чат — три пустых стола', СтолИзЧата.ПОТОЛОК_В_ЧАТЕ, 3);
  проверить('сверх потолка в том же чате — отказ словами, стола нет',
    [await м.стол.позватьКСтолу(команда(640, 'Лишний'), 'домино'),
     м.телеграм.последнее().данные.text.indexOf('уже хватает открытых столов') !== -1,
     м.сервер.сколько('/создать')],
    [false, true, 3]);
  проверить('а в другом чате стол открывается',
    [await м.стол.позватьКСтолу(команда(641, 'Сосед', 'group', -501), 'домино'), м.сервер.сколько('/создать')],
    [true, 4]);
  закрытьВсё(м);
  await дождатьсяСторожей(м.стол);
