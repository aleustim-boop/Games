/* Проверка стола из чата — без Telegram и без сервера комнат.

   Запуск:  node bot/проверка-стола.js

   Модулю подсовываются поддельные Telegram и сервер: всё, что он им
   говорит, записывается, и по записям видно, что он сделал. Сервер
   отвечает так, как отвечает настоящий: на «создать» — как ветка
   безХозяина в server/сервер.js, на «стол» — как сведенияОСтоле
   в server/комнаты.js. Часы тоже поддельные: их двигает пауза сторожа,
   поэтому пять минут ожидания проходят за доли секунды.

   С настоящим сервером тот же модуль проверяет tests/стол-из-чата-сервер.js. */

