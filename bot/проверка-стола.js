let всего = 0;
let провалов = 0;

function проверить(описание, получилось, ожидалось) {
  всего += 1;
  if (JSON.stringify(получилось) === JSON.stringify(ожидалось)) {
    console.log('  ок   — ' + описание);
  } else {
    провалов += 1;
    console.log('  СБОЙ — ' + описание);
    console.log('         ожидали: ' + JSON.stringify(ожидалось));
    console.log('         вышло:   ' + JSON.stringify(получилось));
  }
}

function подождать(мс) {
  return new Promise(function (готово) { setTimeout(готово, мс); });
}

/** Ждём, пока бот отпустит все столы (сторожа доработают), но не дольше секунд. */
async function дождатьсяСторожей(стол) {
  for (let раз = 0; раз < 300 && стол.открытыхСтолов() > 0; раз++) await подождать(10);
}

const ПРОПУСК = 'пропуск-для-проверки';
const СРОК_СЕРВЕРА = 300;     // секунд: столько настоящий сервер держит пустой стол

/** Поддельный сервер комнат: отвечает так, как отвечал бы настоящий. */
function поддельныйСервер() {
  const журнал = [];
  const поведение = {
    лежит: false,          // сервер не отвечает вовсе
    отказ: '',             // на «создать» — отказ этими словами
    безПризнака: false,    // «создать» ответил кодом, но без «безХозяина» (пропуск не признан)
    безСрока: false,       // «создать» не назвал срок
    селНаОпросе: 0,        // с этого опроса за столом человек
    началиНаОпросе: 0,     // с этого опроса партия идёт (людей при этом не называем)
    закрытНаОпросе: 0,     // с этого опроса стола нет
    сбоевПодряд: 0,        // столько первых опросов сервер отвечает 429
    ещёСекунд: null,       // если число — сервер называет такой остаток срока
    опросов: 0,
    столов: 0              // сколько столов сервер уже открыл
  };

  async function запросКСерверу(адрес, путь, тело) {
    журнал.push({ путь: путь, тело: тело });
    if (поведение.лежит) return null;
    if (путь === '/создать') {
      if (поведение.отказ) return { ок: false, номер: 503, данные: { ошибка: поведение.отказ } };
      // Первый стол — ABCD, дальше AB02, AB03…: у настоящего сервера коды разные
      поведение.столов += 1;
      const код = поведение.столов === 1 ? 'ABCD' : 'AB' + String(поведение.столов).padStart(2, '0');
      const данные = { код: код, безХозяина: true, ждётСекунд: СРОК_СЕРВЕРА };
      if (поведение.безПризнака) delete данные.безХозяина;
      if (поведение.безСрока) delete данные.ждётСекунд;
      return { ок: true, номер: 200, данные: данные };
    }
    if (путь.indexOf('/стол?код=') === 0) {
      поведение.опросов += 1;
      const раз = поведение.опросов;
      if (раз <= поведение.сбоевПодряд) {
        return { ок: false, номер: 429, данные: { ошибка: 'Слишком часто' } };
      }
      if (поведение.закрытНаОпросе && раз >= поведение.закрытНаОпросе) {
        return { ок: true, номер: 200, данные: { есть: false, закрылся: true } };
      }
      const сведения = { есть: true, игра: 'дурак', этап: 'ожидание', людей: 0, мест: 6,
        ждётЕщёСекунд: поведение.ещёСекунд === null ? undefined : поведение.ещёСекунд };
      if (поведение.селНаОпросе && раз >= поведение.селНаОпросе) сведения.людей = 1;
      if (поведение.началиНаОпросе && раз >= поведение.началиНаОпросе) сведения.этап = 'игра';
      return { ок: true, номер: 200, данные: сведения };
    }
    return { ок: false, номер: 404, данные: { ошибка: 'Такого адреса на сервере нет' } };
  }

  function сколько(путь) {
    return журнал.filter(function (з) { return з.путь.indexOf(путь) === 0; }).length;
  }

  return { запросКСерверу: запросКСерверу, журнал: журнал, поведение: поведение, сколько: сколько };
}

/** Поддельный Telegram: запоминает, что бот отправил. */
function поддельныйTelegram() {
  const отправлено = [];
  const поведение = { правкаНеПроходит: false, нажатиеУстарело: false };
  let номер = 100;
  async function вызовAPI(метод, данные) {
    отправлено.push({ метод: метод, данные: данные });
    if (метод === 'answerCallbackQuery' && поведение.нажатиеУстарело) {
      throw new Error('Bad Request: query is too old');
    }
    if (метод === 'editMessageText' && поведение.правкаНеПроходит) {
      throw new Error('Bad Request: message to edit not found');
    }
    if (метод === 'sendMessage') return { message_id: ++номер };
    return {};
  }
  function последнее() { return отправлено[отправлено.length - 1] || { метод: '', данные: {} }; }
  function все(метод) { return отправлено.filter(function (о) { return о.метод === метод; }); }
  return { вызовAPI: вызовAPI, отправлено: отправлено, последнее: последнее, все: все, поведение: поведение };
}

const АДРЕС = 'https://пример.рф/комнаты';

function собрать(настройки) {
  const н = настройки || {};
  const сервер = поддельныйСервер();
  const телеграм = поддельныйTelegram();
  const вызовы = [];
  const часы = { сейчас: 1000000 };
  const стол = СтолИзЧата.создать({
    вызовAPI: телеграм.вызовAPI,
    запросКСерверу: сервер.запросКСерверу,
    адресСервера: function () { return н.безАдреса ? '' : АДРЕС; },
    имяБота: function () { return 'ТестБот'; },
    короткоеИмя: 'BoardGames',
    пропускБота: ПРОПУСК,
    названия: Названия,
    отметитьВызов: function (номер, изГруппы) { вызовы.push({ номер: номер, изГруппы: изГруппы }); },
    // Часы двигает пауза сторожа: «прошло 15 секунд» — за миллисекунду
    сейчас: function () { return часы.сейчас; },
    пауза: function (мс) { часы.сейчас += мс; return подождать(1); },
    сказать: function () {}
  });
  return { стол: стол, сервер: сервер, телеграм: телеграм, вызовы: вызовы, часы: часы };
}

function команда(номер, имя, типЧата, чатId) {
  return {
    chat: { id: чатId || -500, type: типЧата || 'group' },
    from: { id: номер, first_name: имя, last_name: 'Фамильев', username: 'nik_' + номер, is_bot: false },
    text: '/играть'
  };
}

/** Разбираем ссылку так же, как игра (разобратьПриглашение в общее/js/сеть.js):
    впереди может стоять «метка_», код — до первого «-», адрес после — base64url. */
function разобратьСсылку(ссылка) {
  let хвост = new URL(ссылка).searchParams.get('startapp') || '';
  let метка = '';
  const сМеткой = /^([a-z]+)_(.*)$/.exec(хвост);
  if (сМеткой) { метка = сМеткой[1]; хвост = сМеткой[2]; }
  const граница = хвост.indexOf('-');
  const код = хвост.slice(0, граница);
  let буквы = хвост.slice(граница + 1).replace(/-/g, '+').replace(/_/g, '/');
  while (буквы.length % 4 !== 0) буквы += '=';
  return { метка: метка, код: код, адрес: Buffer.from(буквы, 'base64').toString('utf8') };
}

function кнопкаИз(сообщение) {
  return сообщение.данные.reply_markup.inline_keyboard[0][0];
}

