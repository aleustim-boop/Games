/* Проверка стола из чата — без Telegram и без сервера комнат.

   Запуск:  node bot/проверка-стола.js

   Модулю подсовываются поддельные Telegram и сервер: всё, что он им
   говорит, записывается, и по записям видно, что он сделал. Ожидание гостей
   укорочено до долей секунды, чтобы прогон занимал секунды, а не минуты. */

'use strict';

const СтолИзЧата = require('./стол-из-чата.js');

let всего = 0;
let провалов = 0;

function проверить(описание, получилось, ожидалось) {
  всего += 1;
  if (JSON.stringify(получилось) === JSON.stringify(ожидалось)) {
    console.log('  ок   — ' + описание);
  } else {
    провалов += 1;
    console.log('  СБОЙ — ' + описание);
    console.log('         ожидали: ' + JSON.stringify(ожидалось));
    console.log('         вышло:   ' + JSON.stringify(получилось));
  }
}

function подождать(мс) {
  return new Promise(function (готово) { setTimeout(готово, мс); });
}

/** Ждём, пока бот отпустит все столы (сторожа доработают), но не дольше секунд. */
async function дождатьсяСторожей(стол) {
  for (let раз = 0; раз < 300 && стол.открытыхСтолов() > 0; раз++) await подождать(10);
}

/** Поддельный сервер комнат: отвечает так, как отвечал бы настоящий. */
function поддельныйСервер() {
  const журнал = [];
  const поведение = { лежит: false, отказ: '', гостьНаОпросе: 0, опросов: 0 };

  async function запросКСерверу(адрес, путь, тело) {
    журнал.push({ путь: путь, тело: тело });
    if (поведение.лежит) return null;
    if (путь === '/создать') {
      if (поведение.отказ) return { ок: false, номер: 503, данные: { ошибка: поведение.отказ } };
      return {
        ок: true, номер: 200,
        данные: { код: 'ABCD', пропуск: 'секрет', состояние: { версия: 1, этап: 'ожидание', застолом: [{ этоЯ: true }] } }
      };
    }
    if (путь === '/что-нового') {
      поведение.опросов += 1;
      if (поведение.гостьНаОпросе && поведение.опросов >= поведение.гостьНаОпросе) {
        return {
          ок: true, номер: 200,
          данные: { изменилось: true, состояние: { версия: 2, этап: 'ожидание',
            застолом: [{ этоЯ: true, имя: 'Бот-зазывала' }, { этоЯ: false, имя: 'Аня' }] } }
        };
      }
      return { ок: true, номер: 200, данные: { изменилось: false } };
    }
    if (путь === '/выйти') return { ок: true, номер: 200, данные: { вышел: true } };
    return { ок: false, номер: 404, данные: { ошибка: 'Такого адреса на сервере нет' } };
  }

  function сколько(путь) {
    return журнал.filter(function (з) { return з.путь === путь; }).length;
  }

  return { запросКСерверу: запросКСерверу, журнал: журнал, поведение: поведение, сколько: сколько };
}

/** Поддельный Telegram: запоминает, что бот отправил. */
function поддельныйTelegram() {
  const отправлено = [];
  let номер = 100;
  async function вызовAPI(метод, данные) {
    отправлено.push({ метод: метод, данные: данные });
    if (метод === 'sendMessage') return { message_id: ++номер };
    return {};
  }
  function последнее() { return отправлено[отправлено.length - 1] || { метод: '', данные: {} }; }
  return { вызовAPI: вызовAPI, отправлено: отправлено, последнее: последнее };
}

const АДРЕС = 'https://пример.рф/комнаты';

function собрать(настройки) {
  const н = настройки || {};
  const сервер = поддельныйСервер();
  const телеграм = поддельныйTelegram();
  const вызовы = [];
  const стол = СтолИзЧата.создать({
    вызовAPI: телеграм.вызовAPI,
    запросКСерверу: сервер.запросКСерверу,
    адресСервера: function () { return н.безАдреса ? '' : АДРЕС; },
    имяБота: function () { return 'ТестБот'; },
    короткоеИмя: 'BoardGames',
    отметитьВызов: function (номер, изГруппы) { вызовы.push({ номер: номер, изГруппы: изГруппы }); },
    ждёмГостей: 250,                                            // вместо десяти минут
    пауза: function (мс) { return подождать(Math.min(мс, 10)); }, // и паузы покороче
    сказать: function () {}
  });
  return { стол: стол, сервер: сервер, телеграм: телеграм, вызовы: вызовы };
}

function команда(номер, имя, типЧата, текст) {
  return {
    chat: { id: -500, type: типЧата || 'group' },
    from: { id: номер, first_name: имя, is_bot: false },
    text: текст || '/играть'
  };
}

/** Разбираем ссылку так же, как игра: код до первого «-», адрес после — base64url. */
function разобратьСсылку(ссылка) {
  const метка = new URL(ссылка).searchParams.get('startapp') || '';
  const граница = метка.indexOf('-');
  const код = метка.slice(0, граница);
  let буквы = метка.slice(граница + 1).replace(/-/g, '+').replace(/_/g, '/');
  while (буквы.length % 4 !== 0) буквы += '=';
  return { код: код, адрес: Buffer.from(буквы, 'base64').toString('utf8') };
}

async function прогон() {
  console.log('');
  console.log('1. Кто-то в группе написал /играть, друг сел');

  let м = собрать();
  м.сервер.поведение.гостьНаОпросе = 2;
  await м.стол.позватьКСтолу(команда(111, 'Вася'));

  const создание = м.сервер.журнал.find(function (з) { return з.путь === '/создать'; });
  проверить('стол создан на компанию, шесть мест, под именем зазывалы',
    создание && создание.тело, { мест: 6, имя: 'Бот-зазывала' });

  const сообщение = м.телеграм.отправлено.find(function (о) { return о.метод === 'sendMessage'; });
  проверить('в чат ушло сообщение', Boolean(сообщение), true);
  проверить('в тексте — кто зовёт', сообщение.данные.text.indexOf('Вася зовёт') !== -1, true);
  const кнопка = сообщение.данные.reply_markup.inline_keyboard[0][0];
  проверить('кнопка — обычная ссылка, а не web_app (в группах web_app не работает)',
    [Boolean(кнопка.url), кнопка.web_app === undefined], [true, true]);
  проверить('ссылка ведёт в мини-приложение бота',
    кнопка.url.indexOf('https://t.me/ТестБот/BoardGames?startapp=ABCD-') === 0, true);
  const разбор = разобратьСсылку(кнопка.url);
  проверить('игра прочтёт из ссылки код стола', разбор.код, 'ABCD');
  проверить('и адрес сервера — в точности наш', разбор.адрес, АДРЕС);
  проверить('в ссылке только разрешённые знаки',
    /^[A-Za-z0-9_-]+$/.test(new URL(кнопка.url).searchParams.get('startapp')), true);
  проверить('вызов посчитан в статистике как из группы', м.вызовы, [{ номер: 111, изГруппы: true }]);

  await дождатьсяСторожей(м.стол);
  проверить('как только сел живой человек — бот вышел из-за стола', м.сервер.сколько('/выйти'), 1);
  проверить('сообщение в чате не трогали (стол живой)',
    м.телеграм.отправлено.some(function (о) { return о.метод === 'editMessageText'; }), false);
  проверить('открытых столов не осталось', м.стол.открытыхСтолов(), 0);

  console.log('');
  console.log('2. Никто не сел — стол закрывается, кнопка не остаётся');

  м = собрать();
  await м.стол.позватьКСтолу(команда(222, 'Петя'));
  проверить('стол держится, пока ждём гостей', м.стол.открытыхСтолов(), 1);
  await дождатьсяСторожей(м.стол);
  проверить('бот вышел — пустую комнату сервер уберёт сам', м.сервер.сколько('/выйти'), 1);
  const правка = м.телеграм.отправлено.find(function (о) { return о.метод === 'editMessageText'; });
  проверить('сообщение в чате исправлено на «стол закрылся»',
    правка && правка.данные.text.indexOf('Стол закрылся') !== -1, true);
  проверить('правится то самое сообщение', правка && правка.данные.message_id, 101);
  проверить('кнопки в исправленном сообщении нет', правка && правка.данные.reply_markup === undefined, true);
  проверить('сервер спрашивали новостями, а не молчали', м.сервер.сколько('/что-нового') > 0, true);

  console.log('');
  console.log('3. Сервер выключен');

  м = собрать();
  м.сервер.поведение.лежит = true;
  await м.стол.позватьКСтолу(команда(333, 'Оля'));
  проверить('честный ответ', м.телеграм.последнее().данные.text.indexOf('Сервер игры сейчас не отвечает') !== -1, true);
  проверить('без кнопки — битой ссылки нет', м.телеграм.последнее().данные.reply_markup, undefined);
  проверить('в статистику не попало', м.вызовы.length, 0);
  проверить('сторожа не завели', м.стол.открытыхСтолов(), 0);

  console.log('');
  console.log('4. Сервер отказал словами');

  м = собрать();
  м.сервер.поведение.отказ = 'Сервер сейчас занят: слишком много начатых партий';
  await м.стол.позватьКСтолу(команда(333, 'Оля'));
  проверить('слова сервера дошли до чата',
    м.телеграм.последнее().данные.text.indexOf('слишком много начатых партий') !== -1, true);

  console.log('');
  console.log('5. Не спамить');

  м = собрать();
  м.сервер.поведение.гостьНаОпросе = 1;
  await м.стол.позватьКСтолу(команда(444, 'Дима'));
  await м.стол.позватьКСтолу(команда(444, 'Дима'));
  проверить('второй стол в ту же минуту не создаём', м.сервер.сколько('/создать'), 1);
  проверить('человеку объяснили', м.телеграм.последнее().данные.text.indexOf('уже открыт') !== -1, true);
  await м.стол.позватьКСтолу(команда(555, 'Лена'));
  проверить('а другому человеку — можно', м.сервер.сколько('/создать'), 2);
  await дождатьсяСторожей(м.стол);

  console.log('');
  console.log('6. Мелочи');

  м = собрать({ безАдреса: true });
  await м.стол.позватьКСтолу(команда(666, 'Ира'));
  проверить('адрес сервера не задан — сказано прямо, к серверу не ходили',
    [м.телеграм.последнее().данные.text.indexOf('не задан адрес') !== -1, м.сервер.журнал.length], [true, 0]);

  м = собрать();
  м.сервер.поведение.гостьНаОпросе = 1;
  await м.стол.позватьКСтолу(команда(777, 'Коля', 'private', '/дурак'));
  проверить('в личке команда тоже работает и считается «не из группы»', м.вызовы, [{ номер: 777, изГруппы: false }]);
  await дождатьсяСторожей(м.стол);

  проверить('ктоТоСел: только бот за столом — нет',
    СтолИзЧата.ктоТоСел({ застолом: [{ этоЯ: true }] }), false);
  проверить('ктоТоСел: сел человек — да',
    СтолИзЧата.ктоТоСел({ застолом: [{ этоЯ: true }, { этоЯ: false }] }), true);
  проверить('ктоТоСел: старая комната без списка — по признаку «соперник пришёл»',
    СтолИзЧата.ктоТоСел({ соперникПришёл: true }), true);
  проверить('адрес с русскими буквами кодируется без потерь',
    разобратьСсылку(СтолИзЧата.ссылкаЗаСтол('Б', 'A', 'WXYZ', 'https://дом.рф:8790/')).адрес, 'https://дом.рф:8790/');

  console.log('');
  console.log('Проверок: ' + всего + ', неудачных: ' + провалов);
  console.log('');
  process.exit(провалов ? 1 : 0);
}

прогон().catch(function (сбой) {
  console.error('Прогон сорвался: ' + сбой.stack);
  process.exit(1);
});
