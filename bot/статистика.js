/* Своя статистика бота: кто и когда заходил.

   Зачем это нужно. Telegram сам показывает строку «столько-то пользователей
   в месяц» только у больших ботов (от десяти тысяч человек за 30 дней),
   и включить её нельзя — эти числа наружу не отдают. Поэтому считаем сами.
   Бот — единственная дверь в игру, значит через него проходят все,
   и счёт получается полный.

   Что храним про человека (нарочно мало — это чужие люди):
     — его номер в Telegram (без номера не отличить одного от другого);
     — день, когда пришёл впервые;
     — день, когда был последний раз;
     — сколько РАЗНЫХ дней заходил — это и есть возвращаемость;
     — сколько раз обращался всего;
     — откуда пришёл в первый раз.
   Ни имён, ни фамилий, ни переписки здесь нет и быть не должно.

   Где храним: bot/данные/статистика.json — обычный текстовый файл рядом
   с ботом. Ни базы, ни библиотек: правило проекта.

   Как храним, чтобы не потерять. Файл никогда не переписывается поверх:
   сначала пишем во временный файл, потом переименовываем его на место
   старого. Переименование — действие мгновенное: бота можно убить в любой
   момент, и на диске останется либо целый старый файл, либо целый новый,
   но не половина.

   Место на будущее: партии, победы и время в игре бот не видит — они живут
   на сервере комнат. Функция «текстОтчёта» принимает вторым доводом готовые
   цифры игры, и когда сервер научится их отдавать, их будет куда положить. */

'use strict';

const fs = require('fs');
const path = require('path');

/* Сколько дней держим подневную сводку. Тридцати хватает на все вопросы
   владельца, шестьдесят — с запасом, чтобы сравнить месяц с прошлым. */
const ДНЕЙ_В_СВОДКЕ = 60;

/* Как называем источники прихода — одними и теми же словами везде. */
const ИСТОЧНИКИ = {
  прямая: 'прямая',            // просто открыл бота и нажал «старт»
  приглашение: 'приглашение',  // пришёл по ссылке друга (в ссылке едет метка)
  группа: 'группа',            // написал боту в группе
  неизвестно: 'неизвестно'
};

/* Как эти источники называть в отчёте владельцу — человеческими словами. */
const НАЗВАНИЯ_ИСТОЧНИКОВ = {
  прямая: 'по прямой ссылке',
  приглашение: 'по приглашению друга',
  группа: 'из группы',
  неизвестно: 'неизвестно откуда'
};

/** День строкой «2026-09-07» по местному времени.
    Местное, а не всемирное: владелец смотрит статистику своими сутками. */
function деньСтрокой(когда) {
  const дата = когда instanceof Date ? когда : new Date(когда);
  const год = дата.getFullYear();
  const месяц = String(дата.getMonth() + 1).padStart(2, '0');
  const число = String(дата.getDate()).padStart(2, '0');
  return год + '-' + месяц + '-' + число;
}

/** Сколько целых суток прошло от одного дня-строки до другого.
    Число может быть отрицательным, если второй день раньше первого. */
function разницаВДнях(деньРаньше, деньПозже) {
  const начало = Date.parse(деньРаньше + 'T00:00:00');
  const конец = Date.parse(деньПозже + 'T00:00:00');
  if (Number.isNaN(начало) || Number.isNaN(конец)) return 0;
  return Math.round((конец - начало) / 86400000);
}

/** Пустая заготовка данных — с неё начинаем, если файла ещё нет. */
function пустыеДанные() {
  return {
    версия: 1,
    люди: {},        // номер человека → что мы про него знаем
    дни: {},         // день → сколько человек заходило, сколько новых, сколько обращений
    источники: {}    // откуда пришли впервые: прямая ссылка, приглашение, группа
  };
}

/** Похоже ли прочитанное на наши данные. Проверяем грубо, но этого хватает:
    если внутри не то, лучше начать заново, чем складывать мусор с числами. */
function данныеПохожиНаНаши(данные) {
  return Boolean(данные) &&
    typeof данные === 'object' &&
    typeof данные.люди === 'object' && данные.люди !== null && !Array.isArray(данные.люди) &&
    typeof данные.дни === 'object' && данные.дни !== null && !Array.isArray(данные.дни);
}

/** Правильное окончание у слова: 1 человек, 2 человека, 5 человек. */
function склонение(число, одна, две, много) {
  const остатокСотни = Math.abs(число) % 100;
  const остатокДесятки = остатокСотни % 10;
  if (остатокСотни > 10 && остатокСотни < 20) return много;
  if (остатокДесятки > 1 && остатокДесятки < 5) return две;
  if (остатокДесятки === 1) return одна;
  return много;
}

/** «12 человек» — число вместе с правильным словом. */
function человек(число) {
  return число + ' ' + склонение(число, 'человек', 'человека', 'человек');
}

/** Доля в процентах, целым числом. Ноль делим спокойно: получится ноль. */
function доля(часть, целое) {
  if (!целое) return 0;
  return Math.round((часть / целое) * 100);
}

/** Создаём счётчик. Путь к файлу можно задать свой — этим пользуется проверка,
    чтобы не трогать настоящие данные живого бота. */
function создатьСчётчик(настройки) {
  const параметры = настройки || {};
  const файл = параметры.файл || path.join(__dirname, 'данные', 'статистика.json');
  const папка = path.dirname(файл);
  // Ругаться в консоль или молчать: проверке лишний шум не нужен
  const сказать = параметры.молча ? function () {} : function (текст) { console.error(текст); };

  let данные = пустыеДанные();

  /** Читаем файл с диска. Битый файл не роняет бота: отодвигаем его в сторону
      под новым именем и начинаем счёт заново. Потерять статистику неприятно,
      но останавливать из-за неё живого бота нельзя. */
  function загрузить() {
    if (!fs.existsSync(файл)) {
      данные = пустыеДанные();
      return;
    }
    let прочитано = null;
    try {
      прочитано = JSON.parse(fs.readFileSync(файл, 'utf8'));
    } catch (сбой) {
      прочитано = null;
    }
    if (!данныеПохожиНаНаши(прочитано)) {
      const отложенный = файл + '.битый-' + Date.now();
      try {
        fs.renameSync(файл, отложенный);
        сказать('Файл статистики оказался испорчен. Отложил его сюда: ' + отложенный + '. Счёт начат заново.');
      } catch (сбой) {
        сказать('Файл статистики испорчен, и отложить его не вышло: ' + сбой.message);
      }
      данные = пустыеДанные();
      return;
    }
    данные = прочитано;
    if (!данные.источники || typeof данные.источники !== 'object') данные.источники = {};
  }

  /** Пишем во временный файл и переименовываем его на место основного.
      Так запись, застигнутая выключением, всегда остаётся целой. */
  function сохранить() {
    try {
      fs.mkdirSync(папка, { recursive: true });
      const временный = файл + '.новая';
      fs.writeFileSync(временный, JSON.stringify(данные, null, 2), 'utf8');
      fs.renameSync(временный, файл);
      return true;
    } catch (сбой) {
      сказать('Не смог сохранить статистику: ' + сбой.message);
      return false;
    }
  }

  /** Подневную сводку держим короткой: старше 60 дней выкидываем. */
  function подрезатьДни(сегодня) {
    for (const день of Object.keys(данные.дни)) {
      if (разницаВДнях(день, сегодня) > ДНЕЙ_В_СВОДКЕ) delete данные.дни[день];
    }
  }

  /** Отмечаем обращение человека к боту.
      событие: { номер, источник, когда }. «когда» можно не передавать —
      тогда берётся текущее время.
      Возвращает правду, если этот человек пришёл к нам впервые. */
  function отметитьЗаход(событие) {
    const запись = событие || {};
    const номер = String(запись.номер || '').trim();
    if (!номер) return false;

    const сегодня = деньСтрокой(запись.когда || new Date());
    const источник = ИСТОЧНИКИ[запись.источник] || ИСТОЧНИКИ.неизвестно;

    let человекЗаписи = данные.люди[номер];
    const новый = !человекЗаписи;
    // Решаем ДО правки записи: сегодня он у нас уже был или это первый раз за сутки
    const первыйРазЗаСутки = новый || человекЗаписи.последний !== сегодня;

    if (новый) {
      человекЗаписи = {
        первый: сегодня,
        последний: сегодня,
        дней: 1,
        обращений: 0,
        источник: источник
      };
      данные.люди[номер] = человекЗаписи;
      данные.источники[источник] = (данные.источники[источник] || 0) + 1;
    } else if (первыйРазЗаСутки) {
      // Новый день того же человека — вот она, возвращаемость
      человекЗаписи.дней = (человекЗаписи.дней || 1) + 1;
      человекЗаписи.последний = сегодня;
    }
    человекЗаписи.обращений = (человекЗаписи.обращений || 0) + 1;

    // Подневная сводка: считаем людей, а не сообщения, поэтому «заходили»
    // растёт только при первом за сутки обращении этого человека
    if (!данные.дни[сегодня]) данные.дни[сегодня] = { заходили: 0, новых: 0, обращений: 0 };
    const сводка = данные.дни[сегодня];
    сводка.обращений = (сводка.обращений || 0) + 1;
    if (первыйРазЗаСутки) сводка.заходили += 1;
    if (новый) сводка.новых += 1;

    подрезатьДни(сегодня);
    return новый;
  }

  /** Все цифры разом. «сейчас» можно задать — этим пользуется проверка.

      Главная мысль про окна: человек «заходил за 7 дней» тогда и только тогда,
      когда его последний заход не старше 7 дней. Поэтому хранить все даты
      посещений не нужно — хватает первого и последнего дня. */
  function цифры(сейчас) {
    const сегодня = деньСтрокой(сейчас || new Date());
    const номера = Object.keys(данные.люди);

    const итог = {
      день: сегодня,
      всегоЛюдей: номера.length,
      всегоОбращений: 0,
      сегодня: 0,
      новыхСегодня: 0,
      вернувшихсяСегодня: 0,
      заНеделю: 0,
      новыхЗаНеделю: 0,
      вернувшихсяЗаНеделю: 0,
      заМесяц: 0,
      новыхЗаМесяц: 0,
      приходилиБольшеОдногоДня: 0,
      источники: Object.assign({}, данные.источники),
      самыйЛюдныйДень: null,
      // Место под цифры сервера комнат: партии, победы, время в игре.
      // Бот их не видит, поэтому здесь честный «ничего не знаем».
      игра: null
    };

    for (const номер of номера) {
      const человекЗаписи = данные.люди[номер];
      итог.всегоОбращений += человекЗаписи.обращений || 0;

      const давноБыл = разницаВДнях(человекЗаписи.последний, сегодня);
      const давноПришёл = разницаВДнях(человекЗаписи.первый, сегодня);

      if (давноБыл === 0) {
        итог.сегодня += 1;
        if (давноПришёл === 0) итог.новыхСегодня += 1;
        else итог.вернувшихсяСегодня += 1;
      }
      if (давноБыл >= 0 && давноБыл < 7) {
        итог.заНеделю += 1;
        if (давноПришёл < 7) итог.новыхЗаНеделю += 1;
        else итог.вернувшихсяЗаНеделю += 1;
      }
      if (давноБыл >= 0 && давноБыл < 30) {
        итог.заМесяц += 1;
        if (давноПришёл < 30) итог.новыхЗаМесяц += 1;
      }
      if ((человекЗаписи.дней || 1) > 1) итог.приходилиБольшеОдногоДня += 1;
    }

    // Самый людный день за то время, что помним
    for (const день of Object.keys(данные.дни)) {
      const сводка = данные.дни[день];
      if (!итог.самыйЛюдныйДень || сводка.заходили > итог.самыйЛюдныйДень.заходили) {
        итог.самыйЛюдныйДень = { день: день, заходили: сводка.заходили, новых: сводка.новых };
      }
    }

    return итог;
  }

  загрузить();

  return {
    отметитьЗаход: отметитьЗаход,
    сохранить: сохранить,
    загрузить: загрузить,
    цифры: цифры,
    путьКФайлу: файл
  };
}

/** Превращаем день «2026-09-07» в «7 сентября». */
const МЕСЯЦЫ = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
  'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];

function деньПоРусски(день) {
  const части = String(день).split('-');
  if (части.length !== 3) return день;
  const номерМесяца = Number(части[1]) - 1;
  if (номерМесяца < 0 || номерМесяца > 11) return день;
  return Number(части[2]) + ' ' + МЕСЯЦЫ[номерМесяца];
}

/** Отчёт владельцу человеческими словами, а не таблицей чисел.

    цифрыИгры — необязательные данные сервера комнат (партии, победы).
    Пока их никто не передаёт, и строки про игру просто не будет. */
function текстОтчёта(итог, цифрыИгры) {
  if (!итог || !итог.всегоЛюдей) {
    return 'Пока к боту не обращался никто. Как только человек нажмёт «старт», он появится в счёте.';
  }

  const строки = [];

  строки.push('Всего у бота побывало ' + человек(итог.всегоЛюдей) + '.');

  строки.push('');
  строки.push('Сегодня заходили ' + человек(итог.сегодня) +
    ' — из них ' + итог.новыхСегодня + ' впервые.');
  строки.push('За неделю заходили ' + человек(итог.заНеделю) +
    ', из них ' + итог.новыхЗаНеделю + ' впервые и ' +
    итог.вернувшихсяЗаНеделю + ' уже бывали раньше.');
  строки.push('За 30 дней заходили ' + человек(итог.заМесяц) +
    ', из них ' + итог.новыхЗаМесяц + ' впервые.');

  строки.push('');
  строки.push('Возвращаемость — главное число:');
  строки.push('приходили больше одного дня ' + итог.приходилиБольшеОдногоДня +
    ' из ' + итог.всегоЛюдей + ' (' + доля(итог.приходилиБольшеОдногоДня, итог.всегоЛюдей) + '%).');
  строки.push('Один заход — это любопытство, второй день — это уже игра.');

  const источники = Object.keys(итог.источники || {});
  if (источники.length) {
    строки.push('');
    строки.push('Откуда приходили (считаем первый приход):');
    for (const имя of источники) {
      строки.push('• ' + (НАЗВАНИЯ_ИСТОЧНИКОВ[имя] || имя) + ' — ' + человек(итог.источники[имя]));
    }
  }

  if (итог.самыйЛюдныйДень && итог.самыйЛюдныйДень.заходили) {
    строки.push('');
    строки.push('Самый людный день — ' + деньПоРусски(итог.самыйЛюдныйДень.день) +
      ': ' + человек(итог.самыйЛюдныйДень.заходили) + '.');
  }

  строки.push('');
  строки.push('Обращений к боту всего: ' + итог.всегоОбращений + '.');

  if (цифрыИгры && цифрыИгры.партий) {
    строки.push('');
    строки.push('Партий сыграно: ' + цифрыИгры.партий + '.');
  } else {
    строки.push('');
    строки.push('Партии, победы и время в игре бот не видит — это знает сервер комнат, ' +
      'их подключим отдельно.');
  }

  return строки.join('\n');
}

module.exports = {
  создатьСчётчик: создатьСчётчик,
  текстОтчёта: текстОтчёта,
  деньСтрокой: деньСтрокой,
  разницаВДнях: разницаВДнях,
  ИСТОЧНИКИ: ИСТОЧНИКИ
};
