/** Слова, по которым спрятанная игра узнаётся в тексте: имя на трёх языках, «в …», метка. */
function примет(строка) {
  const слова = [строка.метка, строка.вИгру];
  for (const язык of ЯЗЫКИ) слова.push(ЯзыкБота.языки.текст(строка.название, язык));
  return слова;
}
function содержит(текст, слово) {
  return String(текст).toLowerCase().indexOf(String(слово).toLowerCase()) !== -1;
}
/** Сколько спрятанных игр упомянуто в тексте. */
function спрятанныхВ(текст) {
  let сколько = 0;
  for (const с of спрятаннаяСтрока) if (примет(с).some(function (с2) { return содержит(текст, с2); })) сколько += 1;
  return сколько;
}
function имяВЯзыке(строка, язык) { return ЯзыкБота.языки.текст(строка.название, язык); }

function вЯзыке(язык, работа) {
  return ЯзыкБота.выполнить({ message: { from: { language_code: язык } } }, работа);
}

