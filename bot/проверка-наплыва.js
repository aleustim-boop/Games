/* Проверка бота под наплывом новых людей — без сети и без токена.

   Запуск:  node bot/проверка-наплыва.js
   Ломающие запуски (должны покраснеть):
            node bot/проверка-наплыва.js --названия=<путь к КОПИИ server/названия.js>
            node bot/проверка-наплыва.js --бот=<путь к КОПИИ bot/бот.js>
   В первой копии выключен фильтр спрятанных игр, во второй возвращён повтор
   при большом retry_after. Копии лежат во временной папке (рядом с первой —
   копия js/игры-реестр.js; во второй пути require сделаны абсолютными),
   настоящие файлы не портят.

   Как устроено: bot/бот.js подключается как модуль (сам он при этом не
   стартует и токен не читает), а https.request подменён заглушкой:
   всё, что бот «шлёт Telegram» и серверу комнат, записывается в журнал,
   а ответы даёт сама проверка. Что проверяем:
     а) приветствие, меню команд, кнопки выбора и inline-карточки не
        содержат спрятанных игр (а неспрятанные — содержат);
     б) команда спрятанной игры стола не создаёт и отвечает «на доработке»;
     в) повторы: 429 с короткой просьбой — один повтор, с долгой — отказ без
        ожидания; обрыв связи — один повтор, тайм-аут — нет; ответы на нажатия
        и оформление — без повторов; язык не путается в пачке; зависшее
        оформление не мешает приёму;
     г) зависший чат не держит остальных; порядок внутри чата сохранён;
     д) сто заходов — не сто записей файла, а при остановке всё записано.

   Спрятанные игры берутся из js/игры-реестра.js (поле «спрятана») напрямую —
   проверка не доверяет тому, что собрал сам бот. Нашлось ноль спрятанных —
   это провал, а не пропуск. */

