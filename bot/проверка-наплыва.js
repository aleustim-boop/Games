https.request = function (параметры, колбэк) {
  const запрос = new EventEmitter();
  запрос.destroy = function (ошибка) { setImmediate(function () { запрос.emit('error', ошибка); }); };
  запрос.end = function (тело) {
    const хост = параметры.hostname;
    const метод = String(параметры.path).split('/').pop();
    let данные = {};
    try { данные = JSON.parse(тело ? тело.toString() : '{}'); } catch (сбой) { данные = {}; }
    const запись = { хост: хост, метод: метод, данные: данные, ждать: параметры.timeout };
    журнал.push(запись);
    const номер = журнал.length;
    Promise.resolve(хост === 'api.telegram.org' ? поведение(метод, данные, запись) : 'сервер-комнат').then(function (ответ) {
      if (ответ === 'сбой-сети') {
        const обрыв = new Error('read ECONNRESET');
        обрыв.code = 'ECONNRESET';   // как у настоящей ошибки соединения в Node
        запрос.emit('error', обрыв);
        return;
      }
      // Тайм-аут: бот сам ловит событие «timeout» и рвёт запрос — так же, как в жизни
      if (ответ === 'тайм-аут') { запрос.emit('timeout'); return; }
      const ответHTTP = new EventEmitter();
      ответHTTP.setEncoding = function () {};
      ответHTTP.statusCode = ответ === 'сервер-комнат' ? 500 : 200;
      колбэк(ответHTTP);
      ответHTTP.emit('data', ответ === 'сервер-комнат' ? '{"ошибка":"проверка"}' : JSON.stringify(ответ));
      ответHTTP.emit('end');
    });
    void номер;
  };
  return запрос;
};

function телеграмные(метод) {
  return журнал.filter(function (з) { return з.хост === 'api.telegram.org' && (!метод || з.метод === метод); });
}
function кСерверуКомнат() {
  return журнал.filter(function (з) { return з.хост !== 'api.telegram.org'; });
}

